//! 骨格の背面へはめた平壁の外面へ出窓を差し込んだ噛み合わせの試験。担当するのは、出窓のワールド姿勢を
//! 接合点の宣言だけから手で導いた値で固定することである。**包含の様式で面上の位置が中心・法線方向のずらしが零
//! である初めての実例であり、寄せない包含が面をぴったり向かい合わせることをこの値が固定する。**
//!
//! **期待値は接合面の姿勢の定義から手で当てた値であり、実装の写しでもBlender側の正解表の写しでもない。**
//! 導出は2段である。骨格の背面のはめ口は`[0,1.3,-1.0]`・向き`[0,0,-1]`にあり、壁の外枠は`[0,1.3,0]`・
//! 向き`[0,0,1]`にあるため、壁は回らずに`[0,0,-1.0]`へ据わり、食い込ませる量0.02が法線の向きへ寄せて
//! `[0,0,-0.98]`になる。
//!
//! 壁の外面の飾り取付は壁ローカルの`[0,1.3,-0.2]`・向き`[0,0,-1]`・上方向`[0,1,0]`であり、その枠は
//! 法線`[0,0,-1]`・縦軸`[0,1,0]`・横軸`[-1,0,0]`である。向かい合う枠は法線と横軸を反転して
//! 法線`[0,0,1]`・縦軸`[0,1,0]`・横軸`[1,0,0]`になる。出窓の壁面差込口は向きも上方向も壁の取付面と同じ
//! であるため自身の枠も法線`[0,0,-1]`・横軸`[-1,0,0]`であり、**天頂軸まわりに180度回して初めて向かい合う。**
//!
//! 回した子の接合点の位置は`[0,0.7,-0.4]`が`[0,0.7,0.4]`になり、子の原点は壁ローカルで
//! `[0,1.3,-0.2] - [0,0.7,0.4] = [0,0.6,-0.6]`、ワールドで`[0,0.6,-1.58]`である。
//! **0.6も-1.58も規則にも手順にも書かれていない。**

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_engine::個体配置;
use blitz_math::メートル;

use crate::joint::{接合種別, 接合面上の位置, 法線方向のずらし};

use super::joint_fit::接合;
use super::mating_fixture::{原点の配置, 壁の接合点を作る, 寄せずに組む, 平行移動が近いか};

/// 骨格の面へ壁を食い込ませる量。2026-08-18の親の目視が確定した値である。
const 壁を骨格の面へ食い込ませる量: f32 = 0.02;

/// 出窓が背面の壁の外面へ、天頂軸まわりに180度回して据わる。
#[test]
fn 出窓が背面の壁の外面へ回して据わる() {
    let 出窓の配置 = 背面の壁へ出窓を差し込んだ配置();
    assert!(
        平行移動が近いか(出窓の配置.平行移動(), [0.0, 0.6, -1.58]),
        "得た平行移動: {:?}",
        出窓の配置.平行移動()
    );
    assert!(天頂軸まわりに半回転した姿勢か(出窓の配置.回転()), "得た回転: {:?}", 出窓の配置.回転());
}

/// 包含の様式は子へ親の倍率をそのまま引き継がせる。壁の倍率が一様な1であるため出窓も1になる。
#[test]
fn 出窓の倍率が壁の倍率を引き継ぐ() {
    assert_eq!(背面の壁へ出窓を差し込んだ配置().スケール(), [1.0, 1.0, 1.0]);
}

/// 骨格の背面のはめ口へ平壁をはめ、その壁の外面の飾り取付へ出窓の壁面差込口を差し込んだ配置。
fn 背面の壁へ出窓を差し込んだ配置() -> 個体配置 {
    let 壁の配置 = 背面の壁の配置();
    assert!(平行移動が近いか(壁の配置.平行移動(), [0.0, 0.0, -0.98]), "壁が想定の位置に無い");
    let 飾り取付 = 壁の接合点を作る("外面の飾り取付", 接合種別::壁面取付, [0.0, 1.3, -0.2], [0.0, 0.0, -1.0], [2.0, 2.6]);
    let 差込口 = 壁の接合点を作る("壁面差込口", 接合種別::壁面差込, [0.0, 0.7, -0.4], [0.0, 0.0, -1.0], [1.8, 1.4]);
    寄せずに組む(&壁の配置, &飾り取付, &差込口, 接合面上の位置::中心()).unwrap().子の配置()
}

/// 原点に据えた骨格の背面のはめ口へ平壁をはめた配置。壁は回らず、食い込ませる量だけ骨格の内側へ寄る。
fn 背面の壁の配置() -> 個体配置 {
    let はめ口 = 壁の接合点を作る("背面のはめ口", 接合種別::壁のはめ口, [0.0, 1.3, -1.0], [0.0, 0.0, -1.0], [2.0, 2.6]);
    let 外枠 = 壁の接合点を作る("壁の外枠", 接合種別::壁の外枠, [0.0, 1.3, 0.0], [0.0, 0.0, 1.0], [2.0, 2.6]);
    let 寄せ = 法線方向のずらし::食い込ませる量から生成する(メートル::生成する(壁を骨格の面へ食い込ませる量)).unwrap();
    接合::組む(&原点の配置(), &はめ口, &外枠, 接合面上の位置::中心(), 寄せ)
        .unwrap()
        .子の配置()
}

/// 天頂軸まわりの180度。クォータニオンは符号違いを同一視する。
fn 天頂軸まわりに半回転した姿勢か(回転: [f32; 4]) -> bool {
    回転[0].abs() < 1.0e-5 && (回転[1].abs() - 1.0).abs() < 1.0e-5 && 回転[2].abs() < 1.0e-5 && 回転[3].abs() < 1.0e-5
}
