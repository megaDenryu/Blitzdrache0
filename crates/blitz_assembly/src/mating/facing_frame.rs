//! 向かい合う枠の組み立てと、そこから子の姿勢を求める工程。
//!
//! **接合とは2つの接合点が向かい合うことである。** 子の接合点の向きが親の向きの逆を向き、
//! 天地が親の天地とそろう配置が、ちょうど1つ決まる。その配置を与える回転をここが求める。
//!
//! 向かい合う枠の横軸を反転させるのは、法線を反転しただけでは右手系が崩れるためである。
//! 法線を`-n`、縦軸を`u`のままにすると、右手系を保つ横軸は`-r`でなければならない。
//! 反転を忘れると鏡像の枠になり、回転では重ねられない組を作ってしまう。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合の定義」

use blitz_math::{クォータニオン, 方向, 部品ローカル};

use crate::joint::接合面の姿勢;

use super::error::接合エラー;

/// 接合面の姿勢を、横軸・縦軸・法線の順に並べた3軸として読む。
pub(super) fn 姿勢の3軸(姿勢: &接合面の姿勢) -> [方向<部品ローカル>; 3] {
    [姿勢.横軸(), 姿勢.縦軸(), 姿勢.法線()]
}

/// 親の接合面と向かい合う枠の3軸。法線と横軸を反転し、縦軸はそのままにする。
pub(super) fn 向かい合う枠の3軸(親の姿勢: &接合面の姿勢) -> [方向<部品ローカル>; 3] {
    [親の姿勢.横軸().逆を向く方向(), 親の姿勢.縦軸(), 親の姿勢.法線().逆を向く方向()]
}

/// 子の部品のローカル座標系を、親の部品のローカル座標系へ写す回転。
pub(super) fn 子から親への回転を求める(
    親の姿勢: &接合面の姿勢,
    子の姿勢: &接合面の姿勢,
) -> Result<クォータニオン<部品ローカル, 部品ローカル>, 接合エラー> {
    let 回転 = クォータニオン::三つの軸を重ねる回転を求める(姿勢の3軸(子の姿勢), 向かい合う枠の3軸(親の姿勢))?;
    Ok(回転)
}
