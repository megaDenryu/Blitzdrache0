//! 一致の様式が面上の位置へ課す判定。受け取るのは呼び出し側が与えた面上の位置、返すのは中心でなければ型付きエラーである。
//!
//! 一致は面と面がそろう関係であり、面に沿って滑らせる自由度を持たない。この判定を置かないと、中心以外の位置が
//! どの検査も受けないまま子の原点へ効く。**子の原点を求める工程は様式を見ずに面上のずらしを足すためである。**
//! 実寸がそろうことだけを見ていた頃は、面上の位置を渡す枝が包含にしか無かったためこの穴が現れなかった。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合には2つの様式があり、検査すべきことが違う」

use crate::joint::接合面上の位置;

use super::error::接合エラー;

pub(super) fn 一致の面上の位置が中心であることを確かめる(面上の位置: 接合面上の位置) -> Result<(), 接合エラー> {
    if 面上の位置.中心か() {
        return Ok(());
    }
    Err(接合エラー::一致の様式で面上の位置が中心でない {
        横: 面上の位置.横().値(),
        縦: 面上の位置.縦().値(),
    })
}
