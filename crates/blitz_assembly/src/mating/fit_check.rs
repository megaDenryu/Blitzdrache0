//! 噛み合いの検査。担当するのは、2つの接合点が繋がってよいかを見て、破れを型付きエラーで言うことだけである。
//! 配置の計算はここでは行わない。
//!
//! 積層と取付で見るものが正反対である。積層は接合面の実寸が一致することを求め、取付は取付側の面が
//! 差込側の面を包含できることを求める。**大きな面のどこかへ小さなものを付ける関係は、面全体が一致する関係ではない。**
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合には2つの様式があり、検査すべきことが違う」

use blitz_engine::個体配置;
use blitz_math::メートル;

use crate::joint::{取付の役割, 接合の様式, 接合点, 接合面上の位置};

use super::error::接合エラー;
use super::scaled_face::接合面の実寸;

pub(super) fn 噛み合いを確かめる(
    親の配置: &個体配置,
    親の接合点: &接合点,
    子の接合点: &接合点,
    面上の位置: 接合面上の位置,
) -> Result<(), 接合エラー> {
    let 種別 = 親の接合点.種別();
    if 種別.対になる種別() != 子の接合点.種別() {
        return Err(接合エラー::種別が対でない {
            親の種別: 種別,
            子の種別: 子の接合点.種別(),
        });
    }
    // 子は親の倍率をそのまま引き継ぐため、両方の実寸を同じ倍率で測る。
    let 親の実寸 = 接合面の実寸::接合点と倍率から求める(親の接合点, 親の配置.スケール());
    let 子の実寸 = 接合面の実寸::接合点と倍率から求める(子の接合点, 親の配置.スケール());
    match 種別.様式() {
        接合の様式::積層 => 積層を確かめる(&親の実寸, &子の実寸),
        接合の様式::取付 { 役割 } => 取付を確かめる(役割, &親の実寸, &子の実寸, 面上の位置),
        接合の様式::未定 => Err(接合エラー::様式が未定である { 種別 }),
    }
}

fn 積層を確かめる(親の実寸: &接合面の実寸, 子の実寸: &接合面の実寸) -> Result<(), 接合エラー> {
    if 親の実寸.一致するか(子の実寸, 親の実寸.寸法から決まる許容差(子の実寸)) {
        return Ok(());
    }
    Err(接合エラー::積層の実寸が一致しない {
        親の幅: 親の実寸.幅().値(),
        親の高さ: 親の実寸.高さ().値(),
        子の幅: 子の実寸.幅().値(),
        子の高さ: 子の実寸.高さ().値(),
    })
}

/// 親がどちらの役割かで、取付側と差込側の割り当てが入れ替わる。
fn 取付を確かめる(
    親の役割: 取付の役割,
    親の実寸: &接合面の実寸,
    子の実寸: &接合面の実寸,
    面上の位置: 接合面上の位置,
) -> Result<(), 接合エラー> {
    let (取付側, 差込側) = match 親の役割 {
        取付の役割::受け入れる側 => (親の実寸, 子の実寸),
        取付の役割::差し込む側 => (子の実寸, 親の実寸),
    };
    let 許容差 = 取付側.寸法から決まる許容差(差込側);
    if !取付側.包含できるか(差込側, 許容差) {
        return Err(接合エラー::差込側が取付側に収まらない {
            取付側の幅: 取付側.幅().値(),
            取付側の高さ: 取付側.高さ().値(),
            差込側の幅: 差込側.幅().値(),
            差込側の高さ: 差込側.高さ().値(),
        });
    }
    はみ出しを確かめる("横", 面上の位置.横(), 取付側.幅(), 差込側.幅(), 許容差)?;
    はみ出しを確かめる("縦", 面上の位置.縦(), 取付側.高さ(), 差込側.高さ(), 許容差)
}

/// 面の中心からずらした位置に差込側を置いたとき、その端が取付側の端を越えないか。
/// 越える量は「ずらしの大きさ + 差込側の半分 − 取付側の半分」である。
fn はみ出しを確かめる(
    軸名: &'static str,
    ずらし: メートル,
    取付側の長さ: メートル,
    差込側の長さ: メートル,
    許容差: メートル,
) -> Result<(), 接合エラー> {
    let はみ出し = ずらし.値().abs() + 差込側の長さ.値() * 0.5 - 取付側の長さ.値() * 0.5;
    if はみ出し <= 許容差.値() {
        return Ok(());
    }
    Err(接合エラー::面上の位置がはみ出す { 軸名, はみ出し })
}
