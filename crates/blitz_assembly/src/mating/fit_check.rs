//! 噛み合いの検査の振り分け。担当するのは、種別が噛み合うことを見て、親の接合面の実寸を測り、様式に応じた判定へ渡し、
//! 決まった子の倍率を返すことである。判定の中身も配置の計算もここでは行わない。
//!
//! 一致と包含で見るものが正反対である。一致は接合面の実寸がそろうことを求め、そろえる倍率を子へ導く。
//! 包含は受け入れる側の面が差し込む側の面を収められることを求め、子は親の倍率をそのまま引き継ぐ。
//! **大きな面のどこかへ小さなものを付ける関係は、面全体がそろう関係ではない。**
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合には2つの様式があり、検査すべきことが違う」

use blitz_engine::個体配置;

use crate::joint::{接合の様式, 接合点, 接合面上の位置};

use super::child_scale::子の倍率;
use super::containment_check::収まることを確かめる;
use super::error::接合エラー;
use super::scaled_face::接合面の実寸;

pub(super) fn 噛み合いを確かめて子の倍率を決める(
    親の配置: &個体配置,
    親の接合点: &接合点,
    子の接合点: &接合点,
    面上の位置: 接合面上の位置,
) -> Result<子の倍率, 接合エラー> {
    let 種別 = 親の接合点.種別();
    if !種別.噛み合うか(子の接合点.種別()) {
        return Err(接合エラー::種別が噛み合わない {
            親の種別: 種別,
            子の種別: 子の接合点.種別(),
        });
    }
    let 親の実寸 = 接合面の実寸::接合点と倍率から求める(親の接合点, 親の配置.スケール())?;
    match 種別.様式() {
        接合の様式::一致 => 子の倍率::接合面の一致から導出する(親の実寸, 子の接合点, 親の配置.スケール()),
        接合の様式::包含 { 役割 } => {
            // 包含では子が親の倍率を引き継ぐため、両方の実寸を同じ倍率で測る。
            let 子の実寸 = 接合面の実寸::接合点と倍率から求める(子の接合点, 親の配置.スケール())?;
            収まることを確かめる(役割, 親の実寸, 子の実寸, 面上の位置, 親の実寸.比べる許容差(子の実寸))?;
            Ok(子の倍率::親から引き継ぐ(親の配置.スケール()))
        }
        接合の様式::未定 => Err(接合エラー::様式が未定である { 種別 }),
    }
}
