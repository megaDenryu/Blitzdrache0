//! 噛み合いの検査の振り分け。担当するのは、種別が対であることを見て、両方の実寸を測り、様式に応じた判定へ渡すことである。
//! 判定の中身も配置の計算もここでは行わない。
//!
//! 一致と包含で見るものが正反対である。一致は接合面の実寸がそろうことを求め、包含は受け入れる側の面が
//! 差し込む側の面を収められることを求める。**大きな面のどこかへ小さなものを付ける関係は、面全体がそろう関係ではない。**
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合には2つの様式があり、検査すべきことが違う」

use blitz_engine::個体配置;
use blitz_math::メートル;

use crate::joint::{接合の様式, 接合点, 接合面上の位置};

use super::containment_check::収まることを確かめる;
use super::error::接合エラー;
use super::scaled_face::接合面の実寸;
use super::size_match_check::実寸がそろうことを確かめる;

pub(super) fn 噛み合いを確かめる(
    親の配置: &個体配置,
    親の接合点: &接合点,
    子の接合点: &接合点,
    面上の位置: 接合面上の位置,
) -> Result<(), 接合エラー> {
    let 種別 = 親の接合点.種別();
    if !種別.噛み合うか(子の接合点.種別()) {
        return Err(接合エラー::種別が噛み合わない {
            親の種別: 種別,
            子の種別: 子の接合点.種別(),
        });
    }
    // 子は親の倍率をそのまま引き継ぐため、両方の実寸を同じ倍率で測る。
    let 親の実寸 = 接合面の実寸::接合点と倍率から求める(親の接合点, 親の配置.スケール())?;
    let 子の実寸 = 接合面の実寸::接合点と倍率から求める(子の接合点, 親の配置.スケール())?;
    let 許容差 = 寸法から決まる許容差(親の実寸, 子の実寸);
    match 種別.様式() {
        接合の様式::一致 => 実寸がそろうことを確かめる(親の実寸, 子の実寸, 許容差),
        接合の様式::包含 { 役割 } => 収まることを確かめる(役割, 親の実寸, 子の実寸, 面上の位置, 許容差),
        接合の様式::未定 => Err(接合エラー::様式が未定である { 種別 }),
    }
}

/// 比べる2つの寸法から決まる許容差。f32は仮数部の桁数が固定であるから表せる刻みが値の大きさに比例する。
/// 大きいほうの寸法の位置で表せる最小の刻みを許容差にすると、丸めだけの差を通し、実際の食い違いを落とせる。
pub(super) fn 寸法から決まる許容差(親の実寸: 接合面の実寸, 子の実寸: 接合面の実寸) -> メートル {
    let 最大 = 親の実寸.最も長い辺().値().max(子の実寸.最も長い辺().値());
    メートル::生成する(最大 * f32::EPSILON)
}
