//! 子の倍率: 接合が決めた、子の部品を置くときの倍率。
//!
//! **規則でなく接合が決める。** 一致の様式では、噛み合う2つの接合面の実寸がそろうことが噛み合いの意味そのものであり、
//! 親の接合面の実寸を子の接合面の宣言で割った比が、子の倍率を一意に決める。木の幹が上へ行くほど細くなるのは、
//! 幹頂部の直径0.4へ幹基部の直径0.5を継ぐと0.8が導かれるからであって、規則が0.8と書くからではない。
//!
//! 親に対する比を絶対の倍率と一緒に持つのは、子の接合点の位置が子の座標系の量であり、親の座標系で組み立てる計算へ
//! 持ち込むときに倍率の比だけ伸ばす必要があるためである。包含の様式では子が親の倍率をそのまま引き継ぐため、
//! この比はちょうど1になり、伸ばす計算が値を1ビットも変えない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「一致の様式は子の倍率を導出する」

use blitz_math::メートル;

use crate::joint::接合点;

use super::error::接合エラー;
use super::scaled_face::接合面の実寸;
use super::size_match_check::実寸がそろうことを確かめる;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 子の倍率 {
    成分: [f32; 3],
    親に対する比: f32,
}

impl 子の倍率 {
    /// 包含の様式が使う。縮んだ親へ原寸の子を付けると宣言と絵が食い違うため、子は親の倍率をそのまま引き継ぐ。
    pub(super) fn 親から引き継ぐ(親の倍率: [f32; 3]) -> Self {
        Self {
            成分: 親の倍率,
            親に対する比: 1.0,
        }
    }

    /// 一致の様式が使う。導くのは接合面に平行な軸の比であり、それを3軸へ置いた一様倍率にする。
    /// 軸ごとに違う倍率を選ぶ自由は、それを要求する部品が実物になるまで持たせない。
    pub(super) fn 接合面の一致から導出する(
        親の実寸: 接合面の実寸,
        子の接合点: &接合点,
        親の倍率: [f32; 3],
    ) -> Result<Self, 接合エラー> {
        let 親の一様な倍率 = 親の倍率が一様であることを確かめる(親の倍率)?;
        let 子の宣言 = 接合面の実寸::接合点と倍率から求める(子の接合点, [1.0; 3])?;
        let 比 = 比を導く(親の実寸, 子の宣言)?;
        let 子の実寸 = 接合面の実寸::接合点と倍率から求める(子の接合点, [比; 3])?;
        実寸がそろうことを確かめる(親の実寸, 子の実寸, 親の実寸.比べる許容差(子の実寸))?;
        Ok(Self {
            成分: [比; 3],
            親に対する比: 比 / 親の一様な倍率,
        })
    }

    pub(super) fn 成分(self) -> [f32; 3] {
        self.成分
    }

    pub(super) fn 親に対する比(self) -> f32 {
        self.親に対する比
    }
}

/// 形の組から1つの比を導く。矩形は幅から導き、高さがそろうかは導いた比で組み直した実寸の照合が見る。
fn 比を導く(親の実寸: 接合面の実寸, 子の宣言: 接合面の実寸) -> Result<f32, 接合エラー> {
    match (親の実寸, 子の宣言) {
        (接合面の実寸::矩形 { 幅: 親の幅, .. }, 接合面の実寸::矩形 { 幅: 子の幅, .. }) => Ok(比を求める(親の幅, 子の幅)),
        (接合面の実寸::円 { 直径: 親の直径 }, 接合面の実寸::円 { 直径: 子の直径 }) => {
            Ok(比を求める(親の直径, 子の直径))
        }
        (親の実寸, 子の宣言) => Err(接合エラー::接合面の形が違う {
            親の実寸: 親の実寸.綴り(),
            子の実寸: 子の宣言.綴り(),
        }),
    }
}

/// 割る先が正で有限であることは`正で有限な長さ`が接合点の生成の時点で確かめてあるため、ここで零除算は起こらない。
fn 比を求める(親の長さ: メートル, 子の長さ: メートル) -> f32 {
    親の長さ.値() / 子の長さ.値()
}

/// 一様でない親の下で一様な子の倍率を導くと、法線方向の倍率が親と子で食い違ったまま連鎖が進む。
/// 実データの家も木も倍率は一様であり、非一様の親が現れたときに軸ごとの導出を設計する。
fn 親の倍率が一様であることを確かめる(親の倍率: [f32; 3]) -> Result<f32, 接合エラー> {
    let 許容差 = 親の倍率.iter().fold(0.0_f32, |最大, 成分| 最大.max(成分.abs())) * f32::EPSILON;
    let そろっている = (親の倍率[0] - 親の倍率[1]).abs() <= 許容差 && (親の倍率[0] - 親の倍率[2]).abs() <= 許容差;
    if そろっている {
        return Ok(親の倍率[0]);
    }
    Err(接合エラー::一致の様式で親の倍率が一様でない { 親の倍率 })
}
