//! 接合: 検査を通った1つの噛み合わせ。**この値が在ることが、噛み合いの全条件を満たしていることの証拠である。**
//! 条件の一覧は`接合エラー`の枝が持つ。
//!
//! 自由関数でなく値の型にするのは、失敗する条件を生成の1地点へ閉じるためである。組み立てる側は
//! 「接合が作れたなら噛み合っている」とだけ知っていればよく、条件を各自で確かめ直さない。
//!
//! 戻り値が既存の`個体配置`であることが重要である。描画側は何も変わらない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合の定義」

use blitz_engine::個体配置;
use blitz_math::{クォータニオン, メートル, ローカル, 位置, 変位, 変換, 部品ローカル};

use crate::joint::{接合点, 接合面上の位置, 法線方向のずらし};

use super::error::接合エラー;
use super::facing_frame::子から親への回転を求める;
use super::fit_check::噛み合いを確かめる;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接合 {
    子の配置: 個体配置,
}

impl 接合 {
    /// 種別の対・様式・実寸の噛み合い・面上の位置のはみ出しを見てから、子の配置を求める。
    /// 子は親の倍率をそのまま引き継ぐ。積層で寸法が一致するには同じ倍率でなければならず、
    /// 取付でも縮んだ親へ原寸の子を付けると宣言と絵が食い違うためである。
    ///
    /// 法線方向のずらしを噛み合いの検査より後に効かせるのは、この値がどの検査も受けないためである。
    /// 離しすぎた配置は、組み上げた部品が親と接しているかの検査がずらしを適用した後の位置で落とす。
    pub fn 組む(
        親の配置: &個体配置,
        親の接合点: &接合点,
        子の接合点: &接合点,
        面上の位置: 接合面上の位置,
        法線方向のずらし: 法線方向のずらし,
    ) -> Result<Self, 接合エラー> {
        噛み合いを確かめる(親の配置, 親の接合点, 子の接合点, 面上の位置)?;
        let 子から親への回転 = 子から親への回転を求める(&親の接合点.姿勢(), &子の接合点.姿勢())?;
        let 親の回転 = 親の回転を読む(親の配置)?;
        let 親ローカルでの子の原点 =
            親ローカルでの子の原点を求める(親の接合点, 子の接合点, 面上の位置, 法線方向のずらし, &子から親への回転);
        let 群ローカルでの子の原点 = 親の変換を組む(親の配置, &親の回転).適用する(親ローカルでの子の原点);
        let 子の回転 = 子から親への回転.続けて回す(&親の回転);
        Ok(Self {
            子の配置: 個体配置::生成する(成分へ写す(群ローカルでの子の原点), 子の回転.成分(), 親の配置.スケール())?,
        })
    }

    /// 子の部品を置くべき配置。描画側はこの値をそのまま個体配置の列へ入れる。
    pub fn 子の配置(&self) -> 個体配置 {
        self.子の配置
    }
}

/// 親のローカル座標系で、子の部品の原点がどこへ来るか。
/// 子の接合点の位置を回してから、親の接合点が指す面上の点から引く。
/// 法線方向のずらしは法線へ沿って足す。法線は親の面から外を向くため、正が離す側・負が食い込ませる側になる。
fn 親ローカルでの子の原点を求める(
    親の接合点: &接合点,
    子の接合点: &接合点,
    面上の位置: 接合面上の位置,
    法線方向のずらし: 法線方向のずらし,
    子から親への回転: &クォータニオン<部品ローカル, 部品ローカル>,
) -> 位置<部品ローカル> {
    let 姿勢 = 親の接合点.姿勢();
    let 面上のずらし = 変位::方向へ進む(姿勢.横軸(), 面上の位置.横()) + 変位::方向へ進む(姿勢.縦軸(), 面上の位置.縦());
    let 寄せ = 変位::方向へ進む(姿勢.法線(), 法線方向のずらし.値());
    let 目標点 = 親の接合点.位置().変位を足す(面上のずらし + 寄せ);
    let 回した子の接合点 = 子から親への回転.変位を回す(子の接合点.位置().原点からの変位());
    目標点.変位を足す(変位::零() - 回した子の接合点)
}

fn 親の変換を組む(
    親の配置: &個体配置, 親の回転: &クォータニオン<部品ローカル, ローカル>
) -> 変換<部品ローカル, ローカル> {
    let 平行移動 = 親の配置.平行移動();
    変換::trsから生成する(
        位置::生成する(
            メートル::生成する(平行移動[0]),
            メートル::生成する(平行移動[1]),
            メートル::生成する(平行移動[2]),
        ),
        *親の回転,
        親の配置.スケール(),
    )
}

/// 個体配置は生成時に回転が正規化済みであることを確かめてあるため、ここで拒まれるのは不変条件が破れた場合だけである。
fn 親の回転を読む(親の配置: &個体配置) -> Result<クォータニオン<部品ローカル, ローカル>, 接合エラー> {
    let 成分 = 親の配置.回転();
    let 回転 = クォータニオン::生成する(成分[0], 成分[1], 成分[2], 成分[3])?;
    Ok(回転)
}

fn 成分へ写す(位置: 位置<ローカル>) -> [f32; 3] {
    [位置.x().値(), 位置.y().値(), 位置.z().値()]
}
