//! 一致の様式の判定。担当するのは、2つの接合面の実寸がそろうかを形ごとに見て、破れを型付きエラーで言うことである。
//!
//! 判定を形ごとに書くのは、そろうことの意味が形で違うためである。矩形は幅と高さの2つがそろうことであり、
//! 円は直径1つがそろうことである。**形の違う組(矩形の面と円の面)は判定を定めず、型付きエラーで拒む。**
//! 実物に無い組を、どちらかの形へ読み替えて黙って通すと、宣言と絵の食い違いが機械を素通りする。

use blitz_math::メートル;

use super::error::接合エラー;
use super::scaled_face::接合面の実寸;

pub(super) fn 実寸がそろうことを確かめる(
    親の実寸: 接合面の実寸,
    子の実寸: 接合面の実寸,
    許容差: メートル,
) -> Result<(), 接合エラー> {
    let そろっている = match (親の実寸, 子の実寸) {
        (
            接合面の実寸::矩形 {
                幅: 親の幅, 高さ: 親の高さ
            },
            接合面の実寸::矩形 {
                幅: 子の幅, 高さ: 子の高さ
            },
        ) => 差が許容差に収まるか(親の幅, 子の幅, 許容差) && 差が許容差に収まるか(親の高さ, 子の高さ, 許容差),
        (接合面の実寸::円 { 直径: 親の直径 }, 接合面の実寸::円 { 直径: 子の直径 }) => {
            差が許容差に収まるか(親の直径, 子の直径, 許容差)
        }
        (親の実寸, 子の実寸) => {
            return Err(接合エラー::接合面の形が違う {
                親の実寸: 親の実寸.綴り(),
                子の実寸: 子の実寸.綴り(),
            });
        }
    };
    if そろっている {
        return Ok(());
    }
    Err(接合エラー::一致の様式で実寸がそろわない {
        親の実寸: 親の実寸.綴り(),
        子の実寸: 子の実寸.綴り(),
    })
}

fn 差が許容差に収まるか(左: メートル, 右: メートル, 許容差: メートル) -> bool {
    (左.値() - 右.値()).abs() <= 許容差.値()
}
