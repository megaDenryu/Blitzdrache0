//! 倍率を掛けた接合面の実寸。受け取るのは接合点と配置の倍率、返すのは横軸と縦軸に沿った実際の長さである。
//!
//! **宣言値どうしを比べてはならない。** 個体配置は非一様の倍率を持ち、木の幹は上へ行くほど細くなる。
//! 親の接合面の実寸は宣言値と倍率から決まるため、宣言値で比べると倍率の変わる連鎖で噛み合いが必ず落ちる。
//!
//! 倍率は部品のローカル座標系の軸ごとに掛かるため、接合面の横軸と縦軸がどちらを向いているかで掛かる量が変わる。
//! 接合面の姿勢が横軸と縦軸を答えるのはこのためである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「倍率を掛けた実寸で判定する」

use blitz_math::{メートル, 方向, 部品ローカル};

use crate::joint::接合点;

pub(super) struct 接合面の実寸 {
    幅: メートル,
    高さ: メートル,
}

impl 接合面の実寸 {
    pub(super) fn 接合点と倍率から求める(接合点: &接合点, 倍率: [f32; 3]) -> Self {
        let 姿勢 = 接合点.姿勢();
        Self {
            幅: 軸に沿って伸びた長さ(接合点.接合面().幅(), 姿勢.横軸(), 倍率),
            高さ: 軸に沿って伸びた長さ(接合点.接合面().高さ(), 姿勢.縦軸(), 倍率),
        }
    }

    pub(super) fn 幅(&self) -> メートル {
        self.幅
    }

    pub(super) fn 高さ(&self) -> メートル {
        self.高さ
    }

    /// 許容差の内側でそろうか。完全一致を求めないのは、部品を別々に作る以上、浮動小数の丸めが必ず入るためである。
    pub(super) fn そろうか(&self, 相手: &Self, 許容差: メートル) -> bool {
        差が許容差に収まるか(self.幅, 相手.幅, 許容差) && 差が許容差に収まるか(self.高さ, 相手.高さ, 許容差)
    }

    /// 相手を包含できるか。受け入れる側が差し込む側を収められるかの判定である。
    pub(super) fn 包含できるか(&self, 相手: &Self, 許容差: メートル) -> bool {
        相手.幅.値() <= self.幅.値() + 許容差.値() && 相手.高さ.値() <= self.高さ.値() + 許容差.値()
    }

    /// 比べる2つの寸法から決まる許容差。f32は仮数部の桁数が固定であるから表せる刻みが値の大きさに比例する。
    /// 大きいほうの寸法の位置で表せる最小の刻みを許容差にすると、丸めだけの差を通し、実際の食い違いを落とせる。
    pub(super) fn 寸法から決まる許容差(&self, 相手: &Self) -> メートル {
        let 最大 = [self.幅.値(), self.高さ.値(), 相手.幅.値(), 相手.高さ.値()]
            .into_iter()
            .fold(0.0_f32, f32::max);
        メートル::生成する(最大 * f32::EPSILON)
    }
}

/// 倍率が掛かった空間で、単位方向に沿った長さがどれだけ伸びるか。倍率を成分ごとに掛けた ベクトルの長さがその比である。
fn 軸に沿って伸びた長さ(宣言の長さ: メートル, 軸: 方向<部品ローカル>, 倍率: [f32; 3]) -> メートル {
    let 伸びた成分 = [軸.x() * 倍率[0], 軸.y() * 倍率[1], 軸.z() * 倍率[2]];
    let 比 = 伸びた成分.iter().map(|成分| 成分 * 成分).sum::<f32>().sqrt();
    宣言の長さ * 比
}

fn 差が許容差に収まるか(左: メートル, 右: メートル, 許容差: メートル) -> bool {
    (左.値() - 右.値()).abs() <= 許容差.値()
}
