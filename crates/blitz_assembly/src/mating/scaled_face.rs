//! 倍率を掛けた接合面の実寸。受け取るのは接合点と配置の倍率、返すのは面の形ごとの実際の長さである。
//!
//! **宣言値どうしを比べてはならない。** 個体配置は非一様の倍率を持ち、木の幹は上へ行くほど細くなる。
//! 親の接合面の実寸は宣言値と倍率から決まるため、宣言値で比べると倍率の変わる連鎖で噛み合いが必ず落ちる。
//!
//! 倍率は部品のローカル座標系の軸ごとに掛かるため、接合面の横軸と縦軸がどちらを向いているかで掛かる量が変わる。
//! 接合面の姿勢が横軸と縦軸を答えるのはこのためである。
//!
//! 円の面は面内のどの方向にも同じ長さを持つ。横軸と縦軸で伸び方が違う倍率が掛かると円が楕円になり、
//! 直径1つでは面を表せなくなるため、その配置を型付きエラーで拒む。
//! 参照: `_doc/設計/部品カタログと接合点.md`「倍率を掛けた実寸で判定する」

use blitz_math::{メートル, 方向, 部品ローカル};

use crate::joint::{接合点, 接合面の形と寸法};

use super::error::接合エラー;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) enum 接合面の実寸 {
    矩形 { 幅: メートル, 高さ: メートル },
    円 { 直径: メートル },
}

impl 接合面の実寸 {
    pub(super) fn 接合点と倍率から求める(接合点: &接合点, 倍率: [f32; 3]) -> Result<Self, 接合エラー> {
        let 姿勢 = 接合点.姿勢();
        let 横の伸び = 軸に沿った伸び(姿勢.横軸(), 倍率);
        let 縦の伸び = 軸に沿った伸び(姿勢.縦軸(), 倍率);
        match 接合点.接合面() {
            接合面の形と寸法::矩形 { 幅, 高さ } => Ok(Self::矩形 {
                幅: 幅.値() * 横の伸び,
                高さ: 高さ.値() * 縦の伸び,
            }),
            接合面の形と寸法::円 { 直径 } => {
                面内の伸びがそろうことを確かめる(横の伸び, 縦の伸び)?;
                Ok(Self::円 {
                    直径: 直径.値() * 横の伸び
                })
            }
        }
    }

    /// この面が持つ最も長い辺。比べる2つの寸法から許容差を決めるために使う。
    pub(super) fn 最も長い辺(self) -> メートル {
        match self {
            Self::矩形 { 幅, 高さ } => メートル::生成する(幅.値().max(高さ.値())),
            Self::円 { 直径 } => 直径,
        }
    }

    /// 比べる2つの寸法から決まる許容差。f32は仮数部の桁数が固定であるから表せる刻みが値の大きさに比例する。
    /// 大きいほうの寸法の位置で表せる最小の刻みを許容差にすると、丸めだけの差を通し、実際の食い違いを落とせる。
    pub(super) fn 比べる許容差(self, 相手: Self) -> メートル {
        メートル::生成する(self.最も長い辺().値().max(相手.最も長い辺().値()) * f32::EPSILON)
    }

    /// 破れの文面へ載せる寸法の綴り。形によって長さの数が違うため、形の側が綴りを持つ。
    pub(super) fn 綴り(self) -> String {
        match self {
            Self::矩形 { 幅, 高さ } => format!("矩形{}かける{}", 幅.値(), 高さ.値()),
            Self::円 { 直径 } => format!("円の直径{}", 直径.値()),
        }
    }
}

/// 倍率が掛かった空間で、その軸に沿った長さが何倍に伸びるか。倍率を成分ごとに掛けた長さを、元の長さで割った比である。
///
/// 注意: 軸の長さで割る。`方向`は長さが1から千分の1まで離れることを許すため(綴りの丸めを受け入れるための幅であり、
/// 無言の正規化はしない)、割らずに長さだけを見ると、倍率が一様でも軸ごとに千分の1の差が出る。
/// その差は円の面が円のままかの判定を誤らせる。軸が正確に長さ1のときは1.0で割ることになり、値は1ビットも変わらない。
fn 軸に沿った伸び(軸: 方向<部品ローカル>, 倍率: [f32; 3]) -> f32 {
    let 伸びた成分 = [軸.x() * 倍率[0], 軸.y() * 倍率[1], 軸.z() * 倍率[2]];
    let 伸びた長さ = 長さを求める(伸びた成分);
    伸びた長さ / 長さを求める([軸.x(), 軸.y(), 軸.z()])
}

fn 長さを求める(成分: [f32; 3]) -> f32 {
    成分.iter().map(|成分| 成分 * 成分).sum::<f32>().sqrt()
}

/// 円の面が円のままでいられるか。許容差は伸びの大きいほうの位置で表せる最小の刻みを、
/// 平方根と除算で丸めが数回積み上がることを見込んで広げたものである。
fn 面内の伸びがそろうことを確かめる(横の伸び: f32, 縦の伸び: f32) -> Result<(), 接合エラー> {
    let 許容差 = 横の伸び.max(縦の伸び) * f32::EPSILON * 8.0;
    if (横の伸び - 縦の伸び).abs() <= 許容差 {
        return Ok(());
    }
    Err(接合エラー::円の接合面へ面内で異なる倍率が掛かっている { 横の伸び, 縦の伸び })
}
