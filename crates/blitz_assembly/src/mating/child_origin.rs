//! 親のローカル座標系で子の部品の原点を求める工程。受け取るのは向かい合う2つの接合点と呼び出し側が与えた
//! 面上の位置・法線方向のずらし・子の倍率、返すのは親の座標系での子の原点である。
//!
//! 子の接合点の位置を回してから、親の接合点が指す面上の点から引く。これが「子の接合点の位置が、親の接合点の
//! 指す面上の点に一致する」という接合の定義そのものである。法線方向のずらしは法線へ沿って足す。
//! 法線は親の面から外を向くため、正が離す側・負が食い込ませる側になる。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合の定義」

use blitz_math::{クォータニオン, 位置, 変位, 部品ローカル};

use crate::joint::{接合点, 接合面上の位置, 法線方向のずらし};

use super::child_scale::子の倍率;

/// 注意: 子の接合点の位置を親に対する比で伸ばしてから引く。この計算は親の座標系で進み、最後に親の変換が
/// 親の倍率を掛けるため、子の倍率が親と違うぶんだけここで先に伸ばしておかないと、子の原点が接合面から外れる。
/// 包含では比がちょうど1であり、掛けても値は1ビットも変わらない。
pub(super) fn 親ローカルでの子の原点を求める(
    親の接合点: &接合点,
    子の接合点: &接合点,
    面上の位置: 接合面上の位置,
    法線方向のずらし: 法線方向のずらし,
    子から親への回転: &クォータニオン<部品ローカル, 部品ローカル>,
    子の倍率: 子の倍率,
) -> 位置<部品ローカル> {
    let 姿勢 = 親の接合点.姿勢();
    let 面上のずらし = 変位::方向へ進む(姿勢.横軸(), 面上の位置.横()) + 変位::方向へ進む(姿勢.縦軸(), 面上の位置.縦());
    let 寄せ = 変位::方向へ進む(姿勢.法線(), 法線方向のずらし.値());
    let 目標点 = 親の接合点.位置().変位を足す(面上のずらし + 寄せ);
    let 伸ばした子の接合点 = 子の接合点.位置().原点からの変位().比で伸ばす(子の倍率.親に対する比());
    let 回した子の接合点 = 子から親への回転.変位を回す(伸ばした子の接合点);
    目標点.変位を足す(変位::零() - 回した子の接合点)
}
