//! 回した親へ子を繋いだときの合成の試験。担当するのは、親の回転が子の位置と姿勢の両方へ効くことを固定することである。
//!
//! **段2の実データは回転をまったく持たなかった。** 正解表との突き合わせが確かめたのは平行移動だけであり、
//! 親を回した合成は一度も動いていない。家並みは軒ごとに向きを変えて建てるため、この道が初めて実行される。
//! 期待値は回転行列を手で当てた値であり、実装の写しではない。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_engine::個体配置;
use blitz_math::{メートル, 位置, 方向, 部品ローカル};

use crate::joint::{接合点, 接合点名, 接合種別, 接合面の姿勢, 接合面上の位置, 接合面寸法};

use super::joint_fit::接合;

/// 天頂軸まわりに4分の1回転した根の配置。天頂軸まわりに角度θ回すと、部品ローカルの(0,0,1)は(sinθ,0,cosθ)へ写る。
fn 四分の一回転した根の配置() -> 個体配置 {
    let 半角 = std::f32::consts::FRAC_PI_4;
    個体配置::生成する([10.0, 0.0, 20.0], [0.0, 半角.sin(), 0.0, 半角.cos()], [1.0; 3]).unwrap()
}

fn 接合点を作る(名前: &str, 種別: 接合種別, 位置成分: [f32; 3], 向き: [f32; 3], 面: [f32; 2]) -> 接合点 {
    let 姿勢 = 接合面の姿勢::生成する(方向::生成する(向き[0], 向き[1], 向き[2]).unwrap(), 方向::生成する(0.0, 1.0, 0.0).unwrap()).unwrap();
    接合点::生成する(
        接合点名::生成する(名前).unwrap(),
        種別,
        位置::<部品ローカル>::生成する(
            メートル::生成する(位置成分[0]),
            メートル::生成する(位置成分[1]),
            メートル::生成する(位置成分[2]),
        ),
        姿勢,
        接合面寸法::生成する(メートル::生成する(面[0]), メートル::生成する(面[1])).unwrap(),
    )
}

/// 実データの3階の正面壁を写した取付側の接合点。法線が+Zであり、部品ローカルで前へ3.2メートル出ている。
fn 正面壁() -> 接合点 {
    接合点を作る("正面壁", 接合種別::壁面取付, [0.0, 1.2, 3.2], [0.0, 0.0, 1.0], [6.7, 2.4])
}

/// 実データの出窓の差込口を写した差込側の接合点。法線が-Zであり、部品ローカルで0.7メートル上にある。
fn 出窓の差込口() -> 接合点 {
    接合点を作る("壁面差込口", 接合種別::壁面差込, [0.0, 0.7, 0.0], [0.0, 0.0, -1.0], [1.8, 1.4])
}

fn 平行移動が近いか(得た: [f32; 3], 期待: [f32; 3]) -> bool {
    得た.iter().zip(期待).all(|(得, 期)| (得 - 期).abs() < 1.0e-4)
}

/// 回さない根では、子の原点は壁の位置から差込口の位置を引いた点、すなわち[0, 0.5, 3.2]である。
#[test]
fn 回さない根では子が壁の正面へ出る() {
    let 根 = 個体配置::生成する([10.0, 0.0, 20.0], [0.0, 0.0, 0.0, 1.0], [1.0; 3]).unwrap();
    let 配置 = 接合::組む(&根, &正面壁(), &出窓の差込口(), 接合面上の位置::中心()).unwrap().子の配置();
    assert!(
        平行移動が近いか(配置.平行移動(), [10.0, 0.5, 23.2]),
        "得た平行移動: {:?}",
        配置.平行移動()
    );
}

/// 天頂軸まわりに4分の1回した根では、+Zへ3.2出ていた点が+Xへ3.2出た点になる。
/// 高さは回転で変わらないため、回さない場合と同じ0.5である。
#[test]
fn 四分の一回した根では子が横へ出る() {
    let 配置 = 接合::組む(&四分の一回転した根の配置(), &正面壁(), &出窓の差込口(), 接合面上の位置::中心())
        .unwrap()
        .子の配置();
    assert!(
        平行移動が近いか(配置.平行移動(), [13.2, 0.5, 20.0]),
        "得た平行移動: {:?}",
        配置.平行移動()
    );
}

/// 子の姿勢にも親の回転が乗る。回した根では子の回転が恒等でなくなり、天頂軸まわりの成分だけが立つ。
#[test]
fn 回した根では子の姿勢にも回転が乗る() {
    let 配置 = 接合::組む(&四分の一回転した根の配置(), &正面壁(), &出窓の差込口(), 接合面上の位置::中心())
        .unwrap()
        .子の配置();
    let 回転 = 配置.回転();
    assert!(回転[3].abs() < 0.999_9, "回した根なのに子の回転が恒等である: {回転:?}");
    assert!(回転[0].abs() < 1.0e-4 && 回転[2].abs() < 1.0e-4, "天頂軸以外の成分が立っている: {回転:?}");
}
