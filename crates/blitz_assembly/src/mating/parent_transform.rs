//! 親の配置を、部品のローカル座標系から群のローカル座標系への変換として読む工程。
//! 受け取るのは親の個体配置、返すのは回転と変換である。
//!
//! 配置が持つのは成分の配列であり、そのままでは空間の型が付かない。ここが1箇所で型の付いた値へ写すことで、
//! 組み立ての計算が生の配列に触れずに済む。

use blitz_engine::個体配置;
use blitz_math::{クォータニオン, メートル, ローカル, 位置, 変換, 部品ローカル};

use super::error::接合エラー;

/// 個体配置は生成時に回転が正規化済みであることを確かめてあるため、ここで拒まれるのは不変条件が破れた場合だけである。
pub(super) fn 親の回転を読む(親の配置: &個体配置) -> Result<クォータニオン<部品ローカル, ローカル>, 接合エラー> {
    let 成分 = 親の配置.回転();
    let 回転 = クォータニオン::生成する(成分[0], 成分[1], 成分[2], 成分[3])?;
    Ok(回転)
}

pub(super) fn 親の変換を組む(
    親の配置: &個体配置,
    親の回転: &クォータニオン<部品ローカル, ローカル>,
) -> 変換<部品ローカル, ローカル> {
    let 平行移動 = 親の配置.平行移動();
    変換::trsから生成する(
        位置::生成する(
            メートル::生成する(平行移動[0]),
            メートル::生成する(平行移動[1]),
            メートル::生成する(平行移動[2]),
        ),
        *親の回転,
        親の配置.スケール(),
    )
}
