/// 一致は面と面がそろう関係であり、面に沿って滑らせる自由度を持たない。中心以外を渡せた頃は、その値が
/// どの検査も受けないまま子の原点へ効いた。子の原点を求める工程が様式を見ずに面上のずらしを足すためである。
#[test]
fn 一致の様式で中心以外の面上の位置を拒む() {
    let 横へずらす = 接合面上の位置::生成する(メートル::生成する(1.5), メートル::生成する(0.0)).unwrap();
    let 誤り = 寄せずに組む(&原点の配置(), &基礎の上面(), &二階の下面(), 横へずらす).unwrap_err();
    assert!(matches!(誤り, 接合エラー::一致の様式で面上の位置が中心でない { .. }), "得た誤り: {誤り}");
}

