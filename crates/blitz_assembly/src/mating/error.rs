//! 接合を組めない事情。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! 寸法の破れが宣言値でなく実寸を持つのは、親に倍率が掛かっていると宣言値どうしを比べても
//! 読み手が食い違いの理由を追えないためである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合の定義」

use blitz_engine::インスタンス群エラー;
use blitz_math::クォータニオンエラー;
use thiserror::Error;

use crate::joint::接合種別;

#[derive(Debug, Clone, PartialEq, Error)]
pub enum 接合エラー {
    #[error("種別が対でない: 親が{親の種別}、子が{子の種別}(親の対は{}である)", .親の種別.対になる種別())]
    種別が対でない {
        親の種別: 接合種別, 子の種別: 接合種別
    },

    #[error("{種別}の様式がまだ決まっていないため接合を組めない")]
    様式が未定である { 種別: 接合種別 },

    #[error("一致の様式なのに接合面の実寸がそろわない: 親が{親の幅}かける{親の高さ}、子が{子の幅}かける{子の高さ}(メートル)")]
    一致の様式で実寸がそろわない {
        親の幅: f32,
        親の高さ: f32,
        子の幅: f32,
        子の高さ: f32,
    },

    #[error(
        "包含なのに差し込む側の面が受け入れる側より大きい: 受け入れる側が{受け入れる側の幅}かける{受け入れる側の高さ}、差し込む側が{差し込む側の幅}かける{差し込む側の高さ}(メートル)"
    )]
    差し込む側が受け入れる側に収まらない {
        受け入れる側の幅: f32,
        受け入れる側の高さ: f32,
        差し込む側の幅: f32,
        差し込む側の高さ: f32,
    },

    #[error("包含で指定した面上の位置が受け入れる側の面からはみ出す: {軸名}方向で{はみ出し}メートル外へ出る")]
    面上の位置がはみ出す { 軸名: &'static str, はみ出し: f32 },

    #[error("接合面の姿勢から子の回転を求められない: {0}")]
    姿勢から回転を求められない(#[from] クォータニオンエラー),

    /// 求めた配置がチャンクの基準原点から離れすぎている場合など、個体配置の不変条件を満たさないとき。
    #[error("求めた子の配置が個体配置として成り立たない: {0}")]
    子の配置が成り立たない(#[from] インスタンス群エラー),
}
