//! 包含の様式の判定。担当するのは、受け入れる側の面が差し込む側の面を収められるかと、指定された面上の位置で
//! 差し込む側が受け入れる側からはみ出さないかを形ごとに見て、破れを型付きエラーで言うことである。
//!
//! 矩形は横と縦を別々に見る。円は面内のどの方向にも同じ長さを持つため、中心からの距離1つで見る。
//! **形の違う組(矩形の面と円の面)は判定を定めず、型付きエラーで拒む。**

use blitz_math::メートル;

use crate::joint::{包含の役割, 接合面上の位置};

use super::error::接合エラー;
use super::scaled_face::接合面の実寸;

/// 親がどちらの役割かで、受け入れる側と差し込む側の割り当てが入れ替わる。
pub(super) fn 収まることを確かめる(
    親の役割: 包含の役割,
    親の実寸: 接合面の実寸,
    子の実寸: 接合面の実寸,
    面上の位置: 接合面上の位置,
    許容差: メートル,
) -> Result<(), 接合エラー> {
    let (受け入れる側, 差し込む側) = match 親の役割 {
        包含の役割::受け入れる側 => (親の実寸, 子の実寸),
        包含の役割::差し込む側 => (子の実寸, 親の実寸),
    };
    match (受け入れる側, 差し込む側) {
        (
            接合面の実寸::矩形 {
                幅: 受ける幅,
                高さ: 受ける高さ,
            },
            接合面の実寸::矩形 {
                幅: 差す幅, 高さ: 差す高さ
            },
        ) => {
            面の大小を確かめる(受け入れる側, 差し込む側, &[(受ける幅, 差す幅), (受ける高さ, 差す高さ)], 許容差)?;
            はみ出しを確かめる("横", 面上の位置.横(), 受ける幅, 差す幅, 許容差)?;
            はみ出しを確かめる("縦", 面上の位置.縦(), 受ける高さ, 差す高さ, 許容差)
        }
        (接合面の実寸::円 { 直径: 受ける直径 }, 接合面の実寸::円 { 直径: 差す直径 }) => {
            面の大小を確かめる(受け入れる側, 差し込む側, &[(受ける直径, 差す直径)], 許容差)?;
            let 中心からの距離 = メートル::生成する(面上の位置.横().値().hypot(面上の位置.縦().値()));
            はみ出しを確かめる("半径", 中心からの距離, 受ける直径, 差す直径, 許容差)
        }
        (受け入れる側, 差し込む側) => Err(接合エラー::接合面の形が違う {
            親の実寸: 受け入れる側.綴り(),
            子の実寸: 差し込む側.綴り(),
        }),
    }
}

/// 面上の位置を見る前に面の大小だけを見る。はみ出しの判定は中心からずらした量を含むため、
/// 「面が大きすぎる」と「ずらしすぎ」を1つの破れに畳むと、読み手が直す先を決められない。
fn 面の大小を確かめる(
    受け入れる側: 接合面の実寸,
    差し込む側: 接合面の実寸,
    辺の組一覧: &[(メートル, メートル)],
    許容差: メートル,
) -> Result<(), 接合エラー> {
    let 収まる = 辺の組一覧
        .iter()
        .all(|(受ける長さ, 差す長さ)| 差す長さ.値() <= 受ける長さ.値() + 許容差.値());
    if 収まる {
        return Ok(());
    }
    Err(接合エラー::差し込む側が受け入れる側に収まらない {
        受け入れる側: 受け入れる側.綴り(),
        差し込む側: 差し込む側.綴り(),
    })
}

/// 面の中心からずらした位置に差し込む側を置いたとき、その端が受け入れる側の端を越えないか。
/// 越える量は「ずらしの大きさ + 差し込む側の半分 − 受け入れる側の半分」である。
fn はみ出しを確かめる(
    軸名: &'static str,
    ずらし: メートル,
    受け入れる側の長さ: メートル,
    差し込む側の長さ: メートル,
    許容差: メートル,
) -> Result<(), 接合エラー> {
    let はみ出し = ずらし.値().abs() + 差し込む側の長さ.値() * 0.5 - 受け入れる側の長さ.値() * 0.5;
    if はみ出し <= 許容差.値() {
        return Ok(());
    }
    Err(接合エラー::面上の位置がはみ出す { 軸名, はみ出し })
}
