//! 一致の様式が子の倍率を導くことの試験。担当するのは、幹の連鎖で倍率が接合面の比から決まることと、
//! 判定が宣言値でなく実寸で行われていることを固定することである。
//!
//! **0.8という数はどこにも書かない。** 幹頂部の直径0.4を幹基部の直径0.5で割った比として出てくることを見る。
//! 連鎖の2段目が0.64になることが、判定に使う親の面が宣言値(いつも0.4)でなく実寸(0.4かける親の倍率)である証拠である。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use crate::joint::接合面上の位置;

use super::mating_fixture::{原点の配置, 寄せずに組む};
use super::scaled_face::接合面の実寸;
use super::size_match_check::実寸がそろうことを確かめる;
use super::tree_fixture::{幹の基部, 幹の頂部, 枝の根元, 枝の生え口, 葉房の根元, 頂芽};

fn 倍率が近いか(得た: [f32; 3], 期待: f32) -> bool {
    得た.iter().all(|成分| (成分 - 期待).abs() < 1.0e-5)
}

#[test]
fn 幹の頂部へ幹の基部を継ぐと倍率が接合面の比になる() {
    let 接合 = 寄せずに組む(&原点の配置(), &幹の頂部(), &幹の基部(), 接合面上の位置::中心()).unwrap();
    assert!(
        倍率が近いか(接合.子の配置().スケール(), 0.4 / 0.5),
        "得た倍率: {:?}",
        接合.子の配置().スケール()
    );
    assert_eq!(接合.子の配置().平行移動()[1], 2.0);
}

/// 連鎖の2段目。親の倍率0.8が掛かった幹頂部の実寸は0.32であり、そこから導かれる比は0.64になる。
/// 宣言値で判定していれば、2段目もまた0.8になる。
#[test]
fn 幹の連鎖は段ごとに倍率を掛け合わせる() {
    let 一段目 = 寄せずに組む(&原点の配置(), &幹の頂部(), &幹の基部(), 接合面上の位置::中心()).unwrap();
    let 二段目 = 寄せずに組む(&一段目.子の配置(), &幹の頂部(), &幹の基部(), 接合面上の位置::中心()).unwrap();
    assert!(
        倍率が近いか(二段目.子の配置().スケール(), 0.64),
        "得た倍率: {:?}",
        二段目.子の配置().スケール()
    );
    // 2段目の下端は、1段目の原点(高さ2.0)から1段目の丈2.0を0.8倍した1.6ぶん上である。
    assert!((二段目.子の配置().平行移動()[1] - 3.6).abs() < 1.0e-5);
}

/// 円どうしの一致。枝の生え口と枝の根元はどちらも直径0.28であり、比は1になる。
#[test]
fn 円どうしの一致は直径の比で噛み合う() {
    let 接合 = 寄せずに組む(&原点の配置(), &枝の生え口(), &枝の根元(), 接合面上の位置::中心()).unwrap();
    assert!(
        倍率が近いか(接合.子の配置().スケール(), 1.0),
        "得た倍率: {:?}",
        接合.子の配置().スケール()
    );
}

/// 細くなった枝の先へ葉房を継ぐと、葉房も同じだけ細くなる。頂芽と葉房の根元はどちらも直径0.14である。
#[test]
fn 細くなった枝の先の葉房は枝と同じ倍率になる() {
    let 幹の二節目 = 寄せずに組む(&原点の配置(), &幹の頂部(), &幹の基部(), 接合面上の位置::中心()).unwrap();
    let 枝 = 寄せずに組む(&幹の二節目.子の配置(), &枝の生え口(), &枝の根元(), 接合面上の位置::中心()).unwrap();
    let 葉房 = 寄せずに組む(&枝.子の配置(), &頂芽(), &葉房の根元(), 接合面上の位置::中心()).unwrap();
    assert!(
        倍率が近いか(枝.子の配置().スケール(), 0.8),
        "得た枝の倍率: {:?}",
        枝.子の配置().スケール()
    );
    assert!(
        倍率が近いか(葉房.子の配置().スケール(), 0.8),
        "得た葉房の倍率: {:?}",
        葉房.子の配置().スケール()
    );
}

/// 判定が実寸で行われていることの直の実証。倍率2の親の実寸と、宣言値のままの子の実寸はそろわない。
/// **この状態は公開の口からは作れない。** 一致の様式が子の倍率を導くため、そろう倍率が必ず選ばれる。
/// 導出が要るのはこの判定が実寸を見るからであり、判定を宣言値へ緩めると連鎖の2段目が黙って通る。
#[test]
fn 倍率を掛けた親の実寸と宣言値のままの子の実寸はそろわない() {
    let 親の実寸 = 接合面の実寸::接合点と倍率から求める(&幹の頂部(), [2.0; 3]).unwrap();
    let 子の宣言のままの実寸 = 接合面の実寸::接合点と倍率から求める(&幹の頂部(), [1.0; 3]).unwrap();
    let 許容差 = メートル::生成する(1.0e-6);
    assert!(実寸がそろうことを確かめる(親の実寸, 子の宣言のままの実寸, 許容差).is_err());
    assert!(実寸がそろうことを確かめる(親の実寸, 親の実寸, 許容差).is_ok());
}
