//! 木の規則が指す部品と、その部品のどの接合点を使うかの指定。
//!
//! 部品IDと接合点名の組を役割ごとの型にするのは、どちらも同じ形の値であり、並べて渡すと取り違えても型が通るためである。
//! 幹の頂部へ葉房の根元を継ぐ誤りは、絵にして初めて見える。

use crate::joint::接合点名;

use super::super::part::部品ID;

/// 幹の一節。上下に継ぐ2つの面を持つ。枝をどの生え口から出すかは節ごとの候補が名前で指すため、この型は持たない。
#[derive(Debug, Clone, PartialEq)]
pub struct 幹の指定 {
    pub 部品: 部品ID,
    pub 基部: 接合点名,
    pub 頂部: 接合点名,
}

/// 幹の側面から生える枝。根元で幹へ付き、頂芽で葉房を受ける。
#[derive(Debug, Clone, PartialEq)]
pub struct 枝の指定 {
    pub 部品: 部品ID,
    pub 根元: 接合点名,
    pub 頂芽: 接合点名,
}

/// 枝の先と幹の頂に付く葉の房。同じ部品が2つの口を持ち、どちらへ継ぐかで使う口が変わる。
/// 2つの名前を1つの型が持つのは、同じ部品であることを型で表すためである。別々の指定に分けると、
/// 枝の先と冠に違う部品を書いた宣言が型を通る。
#[derive(Debug, Clone, PartialEq)]
pub struct 葉房の指定 {
    pub 部品: 部品ID,
    pub 枝の先へ付ける根元: 接合点名, // 枝の頂芽へ継ぐときに使う口(直径0.14)
    pub 幹の頂へ付ける根元: 接合点名, // 幹の頂部へ継いで木の頂を塞ぐ口(直径0.4)
}
