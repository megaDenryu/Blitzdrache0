//! 骨格を連ねた規則が並べる候補と宣言の作り方。継ぎ足しの候補3種と、床を張る宣言と、上面の継ぎ足しの段を作る。
//! 5つの規則そのものは`frame_chain_rule_fixture`が持つ。
//!
//! 規則から分けるのは、この材料が5つの規則から呼ばれるからである。呼び出し側は候補の中身を知らずに
//! 「骨格を継ぐ候補」「屋根を載せる候補」として受け取り、連なりの形だけを自分で決める。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::frame_bay_joint_fixture::{床のはめ口の名前, 骨格の上面の名前};
use super::frame_chain_fixture::平壁を必ず入れるはめ口一覧;
use super::frame_extension::{継ぎ足しの指定, 骨格へ継ぎ足すもの};
use super::frame_fixture::{名前, 屋根の部品, 床板の部品};
use super::frame_floor::骨格へ張る床;

/// 床を張らずに骨格を継ぐ候補。骨格の継ぎ方だけを見る見本の規則が使う。
pub(super) fn 骨格を継ぐ候補(自分の接合点: &str, 面の綴り一覧: &[&str]) -> 骨格へ継ぎ足すもの {
    継いだ骨格が床を張る候補(自分の接合点, 面の綴り一覧, 骨格へ張る床::張らない)
}

pub(super) fn 継いだ骨格が床を張る候補(
    自分の接合点: &str, 面の綴り一覧: &[&str], 床: 骨格へ張る床
) -> 骨格へ継ぎ足すもの {
    骨格へ継ぎ足すもの::骨格を継ぐ {
        自分の接合点: 名前(自分の接合点),
        床,
        はめ口一覧: 平壁を必ず入れるはめ口一覧(面の綴り一覧),
    }
}

/// 床板を1枚張る宣言。骨格の床のはめ口へ床板の外枠を噛み合わせる。
pub(super) fn 床を張る宣言() -> 骨格へ張る床 {
    骨格へ張る床::床を張る {
        部品: 床板の部品(),
        床のはめ口: 名前(床のはめ口の名前),
        床の外枠: 名前("床の外枠"),
    }
}

pub(super) fn 屋根を載せる候補() -> 骨格へ継ぎ足すもの {
    骨格へ継ぎ足すもの::屋根を載せる {
        部品: 屋根の部品(),
        下面: 名前("屋根の下面"),
    }
}

/// 骨格の上面へ継ぎ足す1段。候補の並びをそのまま受ける。
pub(super) fn 上面の継ぎ足し(候補一覧: Vec<骨格へ継ぎ足すもの>) -> 継ぎ足しの指定 {
    継ぎ足しの指定::生成する(名前(骨格の上面の名前), 候補一覧).unwrap()
}
