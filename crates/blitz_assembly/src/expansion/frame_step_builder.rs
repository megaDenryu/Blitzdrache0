//! 一間四方の骨格の手順の組み手: 骨格の規則から手順を組み立てる途中の状態。種と指示の並びと選択の通し番号と、
//! いま壁を受ける骨格の番号を持つ。
//!
//! 家の手順の組み手とも木の手順の組み手とも分けるのは、枝の伸ばし方が違うためである。家は直前に積んだ階の上へ積み、
//! 木は節ごとに番号を覚えて枝の親にする。骨格は骨格そのものを連ね、そのつど空いた面へ壁をはめる。
//! 共通なのは指示を積んで番号を数える規律であり、それは`指示の並びの組み手`が持つ。
//!
//! 壁の親を引数で受けず、いま据わっている骨格の番号を自分で覚えるのは、継いだ骨格の壁を1つ前の骨格へはめる
//! 取り違えを、呼び出し側が書けないようにするためである。骨格を継ぐと、以降の壁はその骨格へはまる。
//!
//! 選択の通し番号をはめ口ごとに1つ進めるのは、4つのはめ口が同じ候補の並びを持つときに、面ごとに違う壁が
//! 選ばれるようにするためである。番号を進めないと4面とも同じ壁になり、面ごとの候補が絵に出ない。
//! 骨格を継いでも番号を数え直さないのは、階や隣どうしで同じ面に同じ壁が並ばないようにするためである。

use crate::joint::接合面上の位置;
use crate::joint::法線方向のずらし;

use super::super::part::部品ID;
use super::frame_extension::骨格の継ぎ足し;
use super::generation_seed::{展開の用途, 生成の種};
use super::instruction::{据えた部品の番号, 接合の指示};
use super::instruction_list_builder::指示の並びの組み手;
use super::opening_choice::{はめ口の指定, はめ口へ入れるもの};

pub(super) struct 一間四方の骨格の手順の組み手 {
    種: 生成の種,
    骨格: 部品ID,
    並びの組み手: 指示の並びの組み手,
    選択の通し番号: u64,
    いま壁を受ける骨格: 据えた部品の番号,
}

impl 一間四方の骨格の手順の組み手 {
    pub(super) fn 根の骨格から始める(種: 生成の種, 骨格: 部品ID) -> Self {
        Self {
            種,
            骨格,
            並びの組み手: 指示の並びの組み手::空から始める(),
            選択の通し番号: 0,
            いま壁を受ける骨格: 据えた部品の番号::根(),
        }
    }

    /// はめ口を順に見て、候補から1件引いた結果が壁なら1枚はめる。「入れない」を引いた面には何も積まない。
    pub(super) fn いま据わっている骨格のはめ口ごとに壁を1枚まで入れる(&mut self, はめ口一覧: &[はめ口の指定]) {
        for はめ口 in はめ口一覧 {
            let 値 = self
                .種
                .混合の生成器を作る()
                .零以上一未満(self.選択の通し番号, 展開の用途::はめ口へ入れるものの選択.番号());
            self.選択の通し番号 += 1;
            let はめ口へ入れるもの::壁をはめる {
                部品,
                外枠,
                法線方向のずらし,
            } = はめ口.値から選ぶ(値)
            else {
                continue;
            };
            self.並びの組み手.接合を1つ積む(接合の指示 {
                親: self.いま壁を受ける骨格,
                親の接合点: はめ口.はめ口().clone(),
                子の部品: 部品.clone(),
                子の接合点: 外枠.clone(),
                面上の位置: 接合面上の位置::中心(),
                法線方向のずらし: *法線方向のずらし,
            });
        }
    }

    /// いま据わっている骨格へ骨格をもう1つ繋ぎ、以降の壁の受け手をその骨格へ移す。
    /// 積層も継ぎも面が向かい合う隣接であるため、法線方向へは寄せない。
    pub(super) fn 骨格をもう1つ継ぐ(&mut self, 継ぎ足し: &骨格の継ぎ足し) {
        self.いま壁を受ける骨格 = self.並びの組み手.接合を1つ積む(接合の指示 {
            親: self.いま壁を受ける骨格,
            親の接合点: 継ぎ足し.直前の骨格の接合点().clone(),
            子の部品: self.骨格.clone(),
            子の接合点: 継ぎ足し.自分の接合点().clone(),
            面上の位置: 接合面上の位置::中心(),
            法線方向のずらし: 法線方向のずらし::寄せない(),
        });
    }

    /// 組み立てた指示の列を取り出して閉じる。以降この組み手は使えない。
    pub(super) fn 指示一覧へ畳む(self) -> Vec<接合の指示> {
        self.並びの組み手.指示一覧へ畳む()
    }
}
