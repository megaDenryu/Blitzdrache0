//! 一間四方の骨格の手順の組み手: 骨格の規則から手順を組み立てる途中の状態。指示の並びと、継ぎ足しの候補を引く器と、
//! 据わった骨格を仕上げる係を持つ。
//!
//! 家の手順の組み手とも木の手順の組み手とも分けるのは、枝の伸ばし方が違うためである。家は直前に積んだ階の上へ積み、
//! 木は節ごとに番号を覚えて枝の親にする。骨格は骨格そのものを連ね、そのつど据わった骨格を仕上げる。
//! 共通なのは指示を積んで番号を数える規律であり、それは`指示の並びの組み手`が持つ。
//!
//! 床と壁と飾りを積む工程を仕上げ係(`frame_wall_step`)へ預けるのは、この組み手が持つのは連なりを伸ばす責務だからである。
//! 壁の親を呼び出し側から受けないのは、継いだ骨格の壁を1つ前の骨格へはめる取り違えを書けなくするためである。
//! 骨格を継ぐと、仕上げ係の受け手がその骨格へ移る。
//!
//! **骨格以外を継ぎ足した時点で連なりが閉じるのは、載せたものが継ぐ口を持たないためである。** 屋根が宣言する
//! 接合点は下面積層1件だけであり、その上へ継げるものが無い。継ぎ足さない枝を引いたときも、新しく据わった骨格が
//! 無いため連なりを伸ばせない。

use crate::joint::{接合面上の位置, 法線方向のずらし};

use super::super::part::部品ID;
use super::choice_drawer::候補を引く器;
use super::frame_extension::{継ぎ足しの指定, 連なりを伸ばせるか, 骨格へ継ぎ足すもの};
use super::frame_floor::骨格へ張る床;
use super::frame_wall_step::据わった骨格の仕上げ係;
use super::generation_seed::{展開の用途, 生成の種};
use super::instruction::接合の指示;
use super::instruction_list_builder::指示の並びの組み手;
use super::opening_choice::はめ口の指定;

pub(super) struct 一間四方の骨格の手順の組み手 {
    骨格: 部品ID,
    並びの組み手: 指示の並びの組み手,
    継ぎ足しの選択: 候補を引く器,
    仕上げ係: 据わった骨格の仕上げ係,
}

impl 一間四方の骨格の手順の組み手 {
    pub(super) fn 根の骨格から始める(種: 生成の種, 骨格: 部品ID) -> Self {
        Self {
            骨格,
            並びの組み手: 指示の並びの組み手::空から始める(),
            継ぎ足しの選択: 候補を引く器::種と用途から始める(種, 展開の用途::骨格へ継ぎ足すものの選択),
            仕上げ係: 据わった骨格の仕上げ係::根の骨格から始める(種),
        }
    }

    /// いま据わっている骨格へ床を1枚張り、はめ口ごとに壁を1枚まではめ、その壁の外面へ飾りを1つまで差し込む。
    pub(super) fn いま据わっている骨格へ床と壁と飾りを入れる(
        &mut self, 床: &骨格へ張る床, はめ口一覧: &[はめ口の指定]
    ) {
        self.仕上げ係.床と壁と飾りを積む(&mut self.並びの組み手, 床, はめ口一覧);
    }

    /// 継ぎ足しの候補を1件引き、骨格なら以降の壁の受け手をその骨格へ移し、屋根なら1件載せて閉じる。
    /// 積層も継ぎも屋根も面が向かい合う隣接であるため、法線方向へは寄せない。
    pub(super) fn 継ぎ足しを1つ実行する(&mut self, 指定: &継ぎ足しの指定) -> 連なりを伸ばせるか {
        let (子の部品, 子の接合点, 継いだ骨格が受けるもの) = match 指定.値から選ぶ(self.継ぎ足しの選択.次の値を引く()) {
            骨格へ継ぎ足すもの::継ぎ足さない => return 連なりを伸ばせるか::閉じた,
            骨格へ継ぎ足すもの::骨格を継ぐ {
                自分の接合点,
                床,
                はめ口一覧,
            } => (self.骨格.clone(), 自分の接合点.clone(), Some((床.clone(), はめ口一覧.clone()))),
            骨格へ継ぎ足すもの::屋根を載せる { 部品, 下面 } => (部品.clone(), 下面.clone(), None),
        };
        let 据えた番号 = self.並びの組み手.接合を1つ積む(接合の指示 {
            親: self.仕上げ係.いま壁を受ける骨格(),
            親の接合点: 指定.直前の骨格の接合点().clone(),
            子の部品,
            子の接合点,
            面上の位置: 接合面上の位置::中心(),
            法線方向のずらし: 法線方向のずらし::寄せない(),
        });
        let Some((床, はめ口一覧)) = 継いだ骨格が受けるもの else {
            return 連なりを伸ばせるか::閉じた;
        };
        self.仕上げ係.受け手を移す(据えた番号);
        self.いま据わっている骨格へ床と壁と飾りを入れる(&床, &はめ口一覧);
        連なりを伸ばせるか::伸ばせる
    }

    /// 組み立てた指示の列を取り出して閉じる。以降この組み手は使えない。
    pub(super) fn 指示一覧へ畳む(self) -> Vec<接合の指示> {
        self.並びの組み手.指示一覧へ畳む()
    }
}
