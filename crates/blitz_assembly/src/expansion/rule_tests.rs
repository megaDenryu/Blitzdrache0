//! 規則からの展開の試験。担当するのは、同じ種から同じ配置表が出ることと、種を変えると選択が変わることと、
//! 候補のどの枝も選ばれうることを固定することである。
//!
//! **決定性がこの段の完了条件である。** 同じ種から違う配置が出ると、焼いた世界が実行ごとに変わり、
//! 検収の判定値がどれも意味を持たなくなる。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::expander::展開器;
use super::expansion_fixture::{原点の配置, 名前, 識別子};
use super::generation_seed::生成の種;
use super::house_rule::家の規則;
use super::placement_table::部品ごとの配置表;
use super::rule::組み立て規則;
use super::wall_choice::{壁面の指定, 壁面の飾り};
use super::wall_fixture::出窓つきのカタログ;
use blitz_math::メートル;

/// 4つの壁面それぞれに「出窓を付ける」と「付けない」の2択を置いた規則。
fn 四面に出窓を選ぶ規則() -> 組み立て規則 {
    let 壁面一覧 = ["正面壁", "背面壁", "左側面壁", "右側面壁"]
        .into_iter()
        .map(|綴り| {
            壁面の指定::生成する(
                名前(綴り),
                vec![
                    壁面の飾り::付けない,
                    壁面の飾り::付ける {
                        部品: 識別子("出窓"),
                        接合点: 名前("差込口"),
                        横のずらし: メートル::生成する(0.0),
                    },
                ],
            )
            .unwrap()
        })
        .collect();
    組み立て規則::家(家の規則::生成する(識別子("土台"), 壁面一覧, Vec::new()))
}

fn 種で展開する(種の値: u64) -> 部品ごとの配置表 {
    展開器::カタログを持たせて生成する(出窓つきのカタログ())
        .規則から展開する(&四面に出窓を選ぶ規則(), 生成の種::値から生成する(種の値), 原点の配置())
        .unwrap()
}

/// 同じ種から2回展開すると、配置表が平行移動も回転も倍率も含めて完全に一致する。
/// 平行移動だけを比べると、回転だけが揺れる形の破れを見逃す。
#[test]
fn 同じ種からは同じ配置表が出る() {
    assert_eq!(種で展開する(20260816), 種で展開する(20260816));
}

/// 種を変えると選ばれる枝が変わる。全部の種で同じ結果になるなら、種が届いていない。
#[test]
fn 種を変えると配置列が変わる() {
    let 一覧: Vec<部品ごとの配置表> = (1..40_u64).map(種で展開する).collect();
    let 先頭 = &一覧[0];
    assert!(
        一覧.iter().any(|配置表| 配置表 != 先頭),
        "39個の種のどれでも同じ配置表になった。種が選択へ届いていない"
    );
}

/// 候補の2つの枝がどちらも選ばれること。片方しか出ないなら、選び方が偏っているか壊れている。
#[test]
fn 候補のどの枝も選ばれうる() {
    let 出窓の件数 = |種の値| 種で展開する(種の値).配置の総数() - 1;
    let 一覧: Vec<usize> = (1..60_u64).map(出窓の件数).collect();
    assert!(一覧.contains(&0), "どの種でも出窓が1つ以上付いた。付けない枝が選ばれていない");
    assert!(一覧.contains(&4), "どの種でも4面すべてには付かなかった。付ける枝の選ばれ方が偏っている");
}

/// 壁面が1つ増えると以降の選択がすべて変わる。選択の添字が規則ぜんたいで通しであることの証拠である。
#[test]
fn 壁面の数が変わると選択の並びが変わる() {
    let 一面だけの規則 = 組み立て規則::家(家の規則::生成する(
        識別子("土台"),
        vec![壁面の指定::生成する(名前("正面壁"), vec![壁面の飾り::付けない]).unwrap()],
        Vec::new(),
    ));
    let 表 = 展開器::カタログを持たせて生成する(出窓つきのカタログ())
        .規則から展開する(&一面だけの規則, 生成の種::値から生成する(1), 原点の配置())
        .unwrap();
    assert_eq!(表.配置の総数(), 1, "付けない枝しか無い規則で土台以外が据わった");
}
