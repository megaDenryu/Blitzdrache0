//! 骨格の上へ屋根を載せた組み立ての試験。担当するのは、屋根が載る高さと、上面の三択のどの枝も選ばれうることと、
//! 骨格以外を継いだ時点で連なりが閉じることを固定することである。
//!
//! **期待値は接合点の宣言から手で当てた値であり、実装の写しではない。** 骨格の上面は部品ローカルの高さ2.60、
//! 屋根の下面は0にあるため、向かい合わせると屋根の原点は2.60へ載る。2段積みの上では階高が2段ぶん累なって5.20になる。
//! **どちらの数も規則には1つも書かれていない。**

#![allow(clippy::unwrap_used)]

use crate::joint::接合点名;

use super::error_rule::規則エラー;
use super::frame_chain_fixture::{屋根の綴り, 平行移動が近いか, 恒等の姿勢か, 綴りごとの配置, 骨格の綴り};
use super::frame_chain_rule_fixture::{
    上面が三択の規則, 屋根を載せた一間四方の家の規則, 屋根を載せた二段の家の規則
};
use super::frame_extension::継ぎ足しの指定;
use super::frame_rule_fixture::規則と種で展開する;

/// 階高。骨格の上面の接合点の高さそのものである。
const 階高メートル: f32 = 2.6;

/// 1ベイの家の屋根が階高の高さへ恒等の姿勢で載る。**高さは規則でなく骨格の上面の宣言が決める。**
#[test]
fn 一間四方の家の屋根が階高の高さへ載る() {
    let 配置表 = 規則と種で展開する(&屋根を載せた一間四方の家の規則(), 1);
    let 屋根一覧 = 綴りごとの配置(&配置表, 屋根の綴り);
    assert_eq!(屋根一覧.len(), 1, "屋根が1件据わっていない");
    assert!(
        平行移動が近いか(屋根一覧[0].平行移動(), [0.0, 階高メートル, 0.0]),
        "得た平行移動: {:?}",
        屋根一覧[0].平行移動()
    );
    assert!(恒等の姿勢か(屋根一覧[0].回転()), "得た回転: {:?}", 屋根一覧[0].回転());
}

/// 2段の家の屋根が階高の2段ぶんの累和の高さへ載る。**Y成分の累和が2段へ伸びることをこの値が固定する。**
#[test]
fn 二段の家の屋根が階高の二段ぶんの高さへ載る() {
    let 配置表 = 規則と種で展開する(&屋根を載せた二段の家の規則(), 1);
    let 骨格一覧 = 綴りごとの配置(&配置表, 骨格の綴り);
    let 屋根一覧 = 綴りごとの配置(&配置表, 屋根の綴り);
    assert_eq!(骨格一覧.len(), 2, "骨格が2件据わっていない");
    assert_eq!(屋根一覧.len(), 1, "屋根が1件据わっていない");
    assert!(平行移動が近いか(骨格一覧[1].平行移動(), [0.0, 階高メートル, 0.0]));
    assert!(
        平行移動が近いか(屋根一覧[0].平行移動(), [0.0, 階高メートル * 2.0, 0.0]),
        "得た平行移動: {:?}",
        屋根一覧[0].平行移動()
    );
}

/// 上面の三択のどの枝も選ばれうる。骨格を積んだ種では屋根が2段目の上へ載り、屋根を引いた種では1段で閉じ、
/// 継ぎ足さない枝を引いた種では骨格1件だけになる。
#[test]
fn 上面の三択のどの枝も選ばれうる() {
    let 規則 = 上面が三択の規則();
    let 姿一覧: Vec<(usize, usize)> = (1..60_u64)
        .map(|種| {
            let 配置表 = 規則と種で展開する(&規則, 種);
            (綴りごとの配置(&配置表, 骨格の綴り).len(), 綴りごとの配置(&配置表, 屋根の綴り).len())
        })
        .collect();
    assert!(姿一覧.contains(&(2, 1)), "骨格を積んで屋根を載せた種が1つも無い");
    assert!(姿一覧.contains(&(1, 1)), "1段で屋根を載せた種が1つも無い");
    assert!(姿一覧.contains(&(1, 0)), "何も継がずに閉じた種が1つも無い");
}

/// **屋根を載せた時点で連なりが閉じる。** 屋根の上へ2枚目の屋根が載る組み立ては、宣言が2段目を持っていても出ない。
/// 屋根が宣言する接合点は下面積層1件だけであり、その上へ継げるものが無いためである。
#[test]
fn 屋根を載せた先へは何も継がない() {
    let 規則 = 上面が三択の規則();
    for 種 in 1..60_u64 {
        let 屋根の件数 = 綴りごとの配置(&規則と種で展開する(&規則, 種), 屋根の綴り).len();
        assert!(屋根の件数 <= 1, "種{種}で屋根が{屋根の件数}件据わった");
    }
}

