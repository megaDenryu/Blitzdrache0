//! 生成の種と、展開が使う用途の区別。担当するのは種を保持して混合の生成器を作ることと、用途に番号を割り当てることである。
//!
//! 混合そのものは`blitz_math`が1つだけ持つ。散布も同じ混合を使うため、ここが写しを持つと同じ種から違う配置が出る。
//!
//! 注意: **番号を散布の用途と重ねない。** 同じ種を使う2つの層が同じ番号を使うと同じ値が出る。
//! 散布は1から7を使っているため、展開は100番台から採る。番号を変えると焼いた配置が全部変わる。

use blitz_math::{決定的な値の生成器, 用途番号};

/// 展開の乱数の種。同じ種と同じ規則からは常に同じ手順が出る。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct 生成の種(u64);

impl 生成の種 {
    pub fn 値から生成する(値: u64) -> Self {
        Self(値)
    }

    /// 個体1件ぶんの種を、通しの番号から分けて作る。同じ規則を何件ぶんも展開する呼び出しがこの口を通る。
    /// 番号をそのまま足すのは、混合関数が入力の1ビットの違いを出力の全体へ広げるためであり、
    /// 隣り合う番号から近い配置が出ることはない。
    pub fn 個体の番号で分けた種を作る(self, 番号: u64) -> Self {
        Self(self.0.wrapping_add(番号))
    }

    pub(super) fn 混合の生成器を作る(self) -> 決定的な値の生成器 {
        決定的な値の生成器::種の値から生成する(self.0)
    }
}

/// 展開が独立した値を必要とする場面の区別。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 展開の用途 {
    /// 壁面へ何を付けるかを候補から選ぶ。
    壁面の飾りの選択,
}

impl 展開の用途 {
    pub(super) fn 番号(self) -> 用途番号 {
        用途番号::番号から生成する(match self {
            Self::壁面の飾りの選択 => 101,
        })
    }
}
