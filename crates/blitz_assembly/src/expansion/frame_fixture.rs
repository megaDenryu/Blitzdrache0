//! 一間四方の骨格の試験の材料のうち、部品の識別子とカタログ。骨格が宣言する接合点11件は`frame_bay_joint_fixture`が、
//! 骨格へ取り付く部品の接合点は`frame_attached_joint_fixture`が、規則の組み方は`frame_rule_fixture`が持つ。
//!
//! カタログを1箇所で組むのは、部品を1件足したときに直す先を1つに保つためである。骨格が床のはめ口を宣言した以上、
//! 床板を積まないカタログは組み上げの検査が「対の相手がカタログに無い」で落とす。
//!
//! 規則と分けているのは、変わる理由が違うためである。部品の顔ぶれはBlender側が部品を収蔵すると変わり、
//! 規則の割り当ては候補の並べ方を変えると変わる。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use crate::joint::接合点名;
use crate::part::{部品ID, 部品カタログ, 部品カタログ組み立て器, 部品定義};

use super::frame_attached_joint_fixture::{壁の外枠, 屋根の下面, 床の外枠, 扉の吊り元};
use super::frame_bay_joint_fixture::骨格の接合点一覧;

/// 壁3種の綴りと、扉の吊り元を持つかどうか。実データの材質スロットは平壁が2・窓壁が3・扉枠付きの壁が2である。
pub(super) const 壁の宣言一覧: [(&str, bool); 3] = [("平壁", false), ("窓壁", false), ("扉枠付きの壁", true)];

pub(super) fn 識別子(綴り: &str) -> 部品ID {
    部品ID::生成する(綴り).unwrap()
}

pub(super) fn 名前(綴り: &str) -> 接合点名 {
    接合点名::生成する(綴り).unwrap()
}

pub(super) fn 骨格の部品() -> 部品ID {
    識別子("一間四方の骨格")
}

pub(super) fn 屋根の部品() -> 部品ID {
    識別子("切妻屋根")
}

pub(super) fn 床板の部品() -> 部品ID {
    識別子("床板")
}

/// 実データの骨格1件と壁3種と切妻屋根と床板を写したカタログ。扉枠付きの壁は扉の吊り元も持つが、様式が未定であるため
/// 対の相手がカタログに無くても組み上げは通る。**その道が実際に通ることをこの材料が一緒に確かめる。**
pub(super) fn 一間四方の骨格のカタログ() -> 部品カタログ {
    let mut 組み立て器 = 部品カタログ組み立て器::空から始める();
    組み立て器
        .部品を1つ積む(骨格の部品(), 部品定義::生成する(骨格の接合点一覧()).unwrap())
        .unwrap();
    for (綴り, 扉の吊り元を持つか) in 壁の宣言一覧 {
        let mut 接合点一覧 = vec![壁の外枠()];
        if 扉の吊り元を持つか {
            接合点一覧.push(扉の吊り元());
        }
        組み立て器.部品を1つ積む(識別子(綴り), 部品定義::生成する(接合点一覧).unwrap()).unwrap();
    }
    組み立て器
        .部品を1つ積む(屋根の部品(), 部品定義::生成する(vec![屋根の下面()]).unwrap())
        .unwrap();
    組み立て器
        .部品を1つ積む(床板の部品(), 部品定義::生成する(vec![床の外枠()]).unwrap())
        .unwrap();
    組み立て器.組み上げる().unwrap()
}
