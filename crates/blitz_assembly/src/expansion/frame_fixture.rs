//! 一間四方の骨格の試験の材料のうち、実データの接合点とカタログ。規則の組み方は`frame_rule_fixture`が持つ。
//!
//! 値は`Mod_Frame_Bay_Single`・`Mod_Wall_HalfTimber_Solid`・`Mod_Wall_HalfTimber_Window`・
//! `Mod_Wall_HalfTimber_DoorFrame`のextrasから読んだ実物であり、雛形ではない。壁の外枠は3種とも同じ位置と姿勢と
//! 寸法で宣言されているため、3種の違いは接合には現れない。**違いはメッシュと材質スロットの数だけである。**
//!
//! 規則と分けているのは、変わる理由が違うためである。接合点はBlender側が部品を直すと変わり、
//! 規則の割り当ては候補の並べ方を変えると変わる。壁面の材料と分けているのは、様式が違うためである。
//! 壁面の対は包含で面の大小を見るが、はめ口の対は一致で実寸がそろうことを求める。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, 位置, 方向, 部品ローカル};

use crate::joint::{接合点, 接合点名, 接合種別, 接合面の姿勢, 接合面の形と寸法};
use crate::part::{部品ID, 部品カタログ, 部品カタログ組み立て器, 部品定義};

/// 骨格の4つのはめ口。名前と外向き法線の組であり、面の中心は法線の向きへ1.0メートル進んだ位置にある。
pub(super) const はめ口の宣言一覧: [(&str, [f32; 3]); 4] = [
    ("正面のはめ口", [0.0, 0.0, 1.0]),
    ("背面のはめ口", [0.0, 0.0, -1.0]),
    ("左面のはめ口", [-1.0, 0.0, 0.0]),
    ("右面のはめ口", [1.0, 0.0, 0.0]),
];

/// 壁3種の綴りと、扉の吊り元を持つかどうか。実データの材質スロットは平壁が2・窓壁が3・扉枠付きの壁が2である。
pub(super) const 壁の宣言一覧: [(&str, bool); 3] = [("平壁", false), ("窓壁", false), ("扉枠付きの壁", true)];

pub(super) fn 識別子(綴り: &str) -> 部品ID {
    部品ID::生成する(綴り).unwrap()
}

pub(super) fn 名前(綴り: &str) -> 接合点名 {
    接合点名::生成する(綴り).unwrap()
}

pub(super) fn 骨格の部品() -> 部品ID {
    識別子("一間四方の骨格")
}

/// 実データの骨格1件と壁3種を写したカタログ。扉枠付きの壁は扉の吊り元も持つが、様式が未定であるため
/// 対の相手がカタログに無くても組み上げは通る。**その道が実際に通ることをこの材料が一緒に確かめる。**
pub(super) fn 一間四方の骨格のカタログ() -> 部品カタログ {
    let mut 組み立て器 = 部品カタログ組み立て器::空から始める();
    let はめ口一覧 = はめ口の宣言一覧
        .into_iter()
        .map(|(名前, 法線)| はめ口の接合点(名前, 法線))
        .collect::<Vec<接合点>>();
    組み立て器.部品を1つ積む(骨格の部品(), 部品定義::生成する(はめ口一覧).unwrap()).unwrap();
    for (綴り, 扉の吊り元を持つか) in 壁の宣言一覧 {
        let mut 接合点一覧 = vec![壁の外枠()];
        if 扉の吊り元を持つか {
            接合点一覧.push(扉の吊り元());
        }
        組み立て器.部品を1つ積む(識別子(綴り), 部品定義::生成する(接合点一覧).unwrap()).unwrap();
    }
    組み立て器.組み上げる().unwrap()
}

/// 骨格のはめ口1件。面の中心は法線の向きへ1.0メートル、床から1.3メートルの高さにある。
fn はめ口の接合点(名前: &str, 法線: [f32; 3]) -> 接合点 {
    接合点を作る(名前, 接合種別::壁のはめ口, [法線[0], 1.3, 法線[2]], 法線, [2.0, 2.6])
}

/// 壁の背面の中心。壁の本体はこの面より奥(部品ローカルのzが-0.2から0)にあるため、向かい合わせると骨格の外側へ出る。
fn 壁の外枠() -> 接合点 {
    接合点を作る("壁の外枠", 接合種別::壁の外枠, [0.0, 1.3, 0.0], [0.0, 0.0, 1.0], [2.0, 2.6])
}

/// 扉枠付きの壁が持つ蝶番の側。様式が未定であるため接合には使えない。
fn 扉の吊り元() -> 接合点 {
    接合点を作る("扉の吊り元", 接合種別::扉の吊り元, [-0.45, 1.0, -0.06], [-1.0, 0.0, 0.0], [0.05, 2.0])
}

/// 天地が天頂を向く接合点。骨格のはめ口も壁の外枠も、実データの上方向はどれも[0, 1, 0]である。
fn 接合点を作る(名前: &str, 種別: 接合種別, 位置成分: [f32; 3], 向き: [f32; 3], 面: [f32; 2]) -> 接合点 {
    let 姿勢 = 接合面の姿勢::生成する(方向を作る(向き), 方向を作る([0.0, 1.0, 0.0])).unwrap();
    接合点::生成する(
        接合点名::生成する(名前).unwrap(),
        種別,
        位置::<部品ローカル>::生成する(
            メートル::生成する(位置成分[0]),
            メートル::生成する(位置成分[1]),
            メートル::生成する(位置成分[2]),
        ),
        姿勢,
        接合面の形と寸法::矩形を生成する(メートル::生成する(面[0]), メートル::生成する(面[1])).unwrap(),
    )
}

fn 方向を作る(成分: [f32; 3]) -> 方向<部品ローカル> {
    方向::生成する(成分[0], 成分[1], 成分[2]).unwrap()
}
