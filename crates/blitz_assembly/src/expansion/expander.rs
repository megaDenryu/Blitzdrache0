//! 展開器: カタログを保持し、組み立て手順から部品ごとの配置表を作る型。
//!
//! カタログをコンストラクタで受け取って保持するのは、展開のたびに呼び出し側へカタログを持参させないためである。
//! 展開器が在るということはカタログが在るということであり、その組で1つの道具になる。
//!
//! **この計算は純粋である。** glTFもファイルも時刻も乱数の外部の源も触らない。同じ手順と同じ根の配置からは
//! 常に同じ配置表が出る。Blenderもウィンドウも起動せずに単体試験できる。

use blitz_engine::個体配置;

use crate::joint::{接合点, 接合点名};
use crate::mating::接合;

use super::super::part::{部品ID, 部品カタログ, 部品定義};
use super::error::展開エラー;
use super::generation_seed::生成の種;
use super::instruction::{接合の指示, 組み立て手順};
use super::placed_parts::据えた部品の列;
use super::placement_table::部品ごとの配置表;
use super::rule::組み立て規則;

pub struct 展開器 {
    カタログ: 部品カタログ,
}

impl 展開器 {
    pub fn カタログを持たせて生成する(カタログ: 部品カタログ) -> Self {
        Self { カタログ }
    }

    /// 根を据えてから、指示を順に実行する。1件でも組めなければ、どの指示で止まったかを添えて型付きエラーで返す。
    pub fn 手順を展開する(
        &self, 手順: &組み立て手順, 根の配置: 個体配置
    ) -> Result<部品ごとの配置表, 展開エラー> {
        self.部品を引く(手順.根の部品())?;
        let mut 据えた列 = 据えた部品の列::根から始める(手順.根の部品().clone(), 根の配置);
        for (添字, 指示) in 手順.指示一覧().iter().enumerate() {
            let 子の配置 = self.指示1件の配置を求める(&据えた列, 添字, 指示)?;
            据えた列.部品を1件据える(指示.子の部品.clone(), 子の配置);
        }
        Ok(据えた列.配置表へ畳む())
    }

    /// 規則と種から手順を生んでから展開する。**同じ種と同じ規則からは常に同じ配置表が出る。**
    /// 規則を手順へ写してから展開するのは、生まれた手順をそのまま検査でき、規則が増えても展開の側が変わらないためである。
    pub fn 規則から展開する(
        &self,
        規則: &組み立て規則,
        種: 生成の種,
        根の配置: 個体配置,
    ) -> Result<部品ごとの配置表, 展開エラー> {
        self.手順を展開する(&規則.種から手順を生む(種), 根の配置)
    }

    fn 指示1件の配置を求める(
        &self, 据えた列: &据えた部品の列, 添字: usize, 指示: &接合の指示
    ) -> Result<個体配置, 展開エラー> {
        let 親 = 据えた列.番号で引く(指示.親).ok_or(展開エラー::親がまだ据わっていない {
            指示の添字: 添字,
            親の番号: 指示.親.番号を返す(),
            据えた件数: 据えた列.据えた件数(),
        })?;
        let 親の接合点 = self.接合点を引く(親.識別子(), &指示.親の接合点)?;
        let 子の接合点 = self.接合点を引く(&指示.子の部品, &指示.子の接合点)?;
        let 接合 = 接合::組む(&親.配置(), 親の接合点, 子の接合点, 指示.面上の位置, 指示.法線方向のずらし).map_err(|誤り| {
            展開エラー::接合を組めない {
                指示の添字: 添字, 誤り
            }
        })?;
        Ok(接合.子の配置())
    }

    fn 部品を引く(&self, 識別子: &部品ID) -> Result<&部品定義, 展開エラー> {
        self.カタログ.部品を引く(識別子).ok_or_else(|| 展開エラー::部品がカタログに無い {
            部品の識別子: 識別子.clone(),
        })
    }

    fn 接合点を引く(&self, 識別子: &部品ID, 名前: &接合点名) -> Result<&接合点, 展開エラー> {
        self.部品を引く(識別子)?
            .接合点を名前で引く(名前)
            .ok_or_else(|| 展開エラー::接合点が部品に無い {
                部品の識別子: 識別子.clone(),
                接合点の名前: 名前.clone(),
            })
    }
}
