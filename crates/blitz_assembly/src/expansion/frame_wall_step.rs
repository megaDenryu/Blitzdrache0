//! 据わった骨格1つの仕上げ係: いま壁を受ける骨格の番号と、壁と飾りの2つの候補を引く器を持ち、
//! 床を1枚張り、はめ口ごとに壁を1枚まではめ、その壁の外面へ飾りを1つまで差し込む。
//!
//! 手順の組み手から分けるのは、責務が違うためである。組み手は連なりを伸ばして指示の並びを所有し、
//! この係は据わった骨格1つを仕上げることだけを受け持つ。**壁と飾りの2つの器をこの係が持つことで、
//! 組み手は連なりの器だけを持てばよくなる。**
//!
//! 指示の並びの組み手を引数で受けて保持しないのは、指示の並びの所有者が手順の組み手だからである。
//! この係が写しを持つと、積んだ番号の数え方が2つに分かれる。
//!
//! **飾りの親は骨格でなく、いま据えたばかりの壁である。** 壁を積んだ結果として返る番号をそのまま飾りの親に使う。
//! 壁が入らなかった面では飾りの候補を引かない。壁の無い面へ飾りだけが浮くことは起こりえない。

use super::choice_drawer::候補を引く器;
use super::frame_floor::骨格へ張る床;
use super::generation_seed::{展開の用途, 生成の種};
use super::instruction::据えた部品の番号;
use super::instruction_list_builder::指示の並びの組み手;
use super::opening_choice::はめ口の指定;

pub(super) struct 据わった骨格の仕上げ係 {
    いま壁を受ける骨格: 据えた部品の番号,
    壁の選択: 候補を引く器,
    飾りの選択: 候補を引く器,
}

impl 据わった骨格の仕上げ係 {
    pub(super) fn 根の骨格から始める(種: 生成の種) -> Self {
        Self {
            いま壁を受ける骨格: 据えた部品の番号::根(),
            壁の選択: 候補を引く器::種と用途から始める(種, 展開の用途::はめ口へ入れるものの選択),
            飾りの選択: 候補を引く器::種と用途から始める(種, 展開の用途::壁の外面の飾りの選択),
        }
    }

    pub(super) fn いま壁を受ける骨格(&self) -> 据えた部品の番号 {
        self.いま壁を受ける骨格
    }

    /// 以降の壁と飾りを受ける骨格を、新しく据わった骨格へ移す。
    pub(super) fn 受け手を移す(&mut self, 骨格の番号: 据えた部品の番号) {
        self.いま壁を受ける骨格 = 骨格の番号;
    }

    /// 宣言があれば床を1枚張り、はめ口を順に見て壁と飾りを積む。
    /// はめ口ごとに1つ引くのは、4つのはめ口が同じ候補の並びを持つときに面ごとに違う壁が選ばれるようにするためである。
    /// **床は候補を引かない。** 理由は`frame_floor`が持つ。
    pub(super) fn 床と壁と飾りを積む(
        &mut self, 並びの組み手: &mut 指示の並びの組み手, 床: &骨格へ張る床, はめ口一覧: &[はめ口の指定]
    ) {
        if let Some(指示) = 床.指示にする(self.いま壁を受ける骨格) {
            並びの組み手.接合を1つ積む(指示);
        }
        for はめ口 in はめ口一覧 {
            self.壁を1枚はめて外面へ飾りを差し込む(並びの組み手, はめ口);
        }
    }

    /// はめ口から引いた候補が壁なら1枚はめ、続けてその壁の外面の飾りを1つ引いて差し込む。
    /// 「入れない」を引いた面には壁も飾りも積まない。
    fn 壁を1枚はめて外面へ飾りを差し込む(
        &mut self, 並びの組み手: &mut 指示の並びの組み手, はめ口: &はめ口の指定
    ) {
        let 候補 = はめ口.値から選ぶ(self.壁の選択.次の値を引く());
        let Some(壁の指示) = 候補.指示にする(self.いま壁を受ける骨格, はめ口.はめ口()) else {
            return;
        };
        let 据えた壁の番号 = 並びの組み手.接合を1つ積む(壁の指示);
        let Some(飾りの指定) = 候補.外面の飾りの指定() else {
            return;
        };
        let 飾り = 飾りの指定.値から選ぶ(self.飾りの選択.次の値を引く());
        if let Some(飾りの指示) = 飾り.指示にする(据えた壁の番号, 飾りの指定.飾り取付()) {
            並びの組み手.接合を1つ積む(飾りの指示);
        }
    }
}
