//! 組み立て規則: 何をどう組み立てるかの種類を数え上げた判別共用体。
//!
//! トレイトでなく判別共用体にするのは、本リポジトリが「条件分岐はenumと網羅的match」を規約にしているためである。
//! 規則の種類が増えるたびに枝を足し、網羅性を型で保つ。
//!
//! **枝は家と木の2つである。** 規則を1つ足すと、この網羅的matchへ枝を書き足すまでコンパイルが通らない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「部品カタログと展開器」

use super::generation_seed::生成の種;
use super::house_rule::家の規則;
use super::instruction::組み立て手順;
use super::tree_rule::木の規則;

#[derive(Debug, Clone, PartialEq)]
pub enum 組み立て規則 {
    家(家の規則),
    木(木の規則),
}

impl 組み立て規則 {
    /// 種から手順を生む。同じ種と同じ規則からは常に同じ手順が出る。
    pub(super) fn 種から手順を生む(&self, 種: 生成の種) -> 組み立て手順 {
        match self {
            Self::家(規則) => 規則.種から手順を生む(種),
            // 木の規則は幹の節数も枝の位置も自分で決めており、種から選ぶ余地をまだ持たない。
            Self::木(規則) => 規則.手順を生む(),
        }
    }
}
