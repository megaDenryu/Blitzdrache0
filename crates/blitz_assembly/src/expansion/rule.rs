//! 組み立て規則: 何をどう組み立てるかの種類を数え上げた判別共用体。
//!
//! トレイトでなく判別共用体にするのは、本リポジトリが「条件分岐はenumと網羅的match」を規約にしているためである。
//! 規則の種類が増えるたびに枝を足し、網羅性を型で保つ。
//!
//! **枝は家と木と一間四方の骨格の3つである。** 規則を1つ足すと、この網羅的matchへ枝を書き足すまでコンパイルが通らない。
//!
//! 一間四方の骨格を家の枝に含めないのは、組み立ての形が違うためである。家は土台の上へ階を積み、階の壁面へ飾りを
//! 差し込む。骨格は積むものを持たず、はめ口へ壁をはめるだけである。1つの型で表そうとすると、どちらの規則でも
//! 使わない欄が生まれる。
//! 参照: `_doc/設計/部品カタログと接合点.md`「部品カタログと展開器」

use super::frame_rule::一間四方の骨格の規則;
use super::generation_seed::生成の種;
use super::house_rule::家の規則;
use super::instruction::組み立て手順;
use super::tree_rule::木の規則;

#[derive(Debug, Clone, PartialEq)]
pub enum 組み立て規則 {
    家(家の規則),
    木(木の規則),
    一間四方の骨格(一間四方の骨格の規則),
}

impl 組み立て規則 {
    /// 種から手順を生む。同じ種と同じ規則からは常に同じ手順が出る。
    pub(super) fn 種から手順を生む(&self, 種: 生成の種) -> 組み立て手順 {
        match self {
            Self::家(規則) => 規則.種から手順を生む(種),
            Self::木(規則) => 規則.種から手順を生む(種),
            Self::一間四方の骨格(規則) => 規則.種から手順を生む(種),
        }
    }
}
