/// 候補が空の壁面の指定を拒む。選べない選択肢は「選んだ結果が無い」という半端な状態を作る。
#[test]
fn 候補が空の壁面の指定を拒む() {
    let 結果 = super::wall_choice::壁面の指定::生成する(名前("正面壁"), Vec::new());
    assert!(
        matches!(結果, Err(super::error_rule::規則エラー::壁面の候補が空である { .. })),
        "候補が空の指定を受け入れてしまった"
    );
}
