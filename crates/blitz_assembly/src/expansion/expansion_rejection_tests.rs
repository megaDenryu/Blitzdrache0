//! 手順の破れを拒むことの試験。担当するのは、カタログに無い部品・部品に無い接合点・まだ据わっていない親を
//! 指す手順が、型付きエラーで止まることを固定することである。
//!
//! 正の対照と分けているのは、拒む側が前提の一覧であり、前提を1つ足すたびにここへ1件増えるためである。
//! 材料は`expansion_fixture`が持つ。

#![allow(clippy::unwrap_used)]

use crate::joint::{接合面上の位置, 法線方向のずらし};

use super::error::展開エラー;
use super::expander::展開器;
use super::expansion_fixture::{三階建てのカタログ, 原点の配置, 名前, 識別子};
use super::instruction::{据えた部品の番号, 接合の指示, 組み立て手順};

#[test]
fn カタログに無い部品を指す手順を拒む() {
    let 手順 = 組み立て手順::根と指示から生成する(識別子("屋根"), Vec::new());
    let 誤り = 展開器::カタログを持たせて生成する(三階建てのカタログ())
        .手順を展開する(&手順, 原点の配置())
        .unwrap_err();
    assert!(matches!(誤り, 展開エラー::部品がカタログに無い { .. }), "得た誤り: {誤り}");
}

#[test]
fn 部品に無い接合点を指す手順を拒む() {
    let 手順 = 組み立て手順::根と指示から生成する(
        識別子("基礎"),
        vec![接合の指示 {
            親: 据えた部品の番号::根(),
            親の接合点: 名前("側面"),
            子の部品: 識別子("2階"),
            子の接合点: 名前("下面"),
            面上の位置: 接合面上の位置::中心(),
            法線方向のずらし: 法線方向のずらし::寄せない(),
        }],
    );
    let 誤り = 展開器::カタログを持たせて生成する(三階建てのカタログ())
        .手順を展開する(&手順, 原点の配置())
        .unwrap_err();
    assert!(matches!(誤り, 展開エラー::接合点が部品に無い { .. }), "得た誤り: {誤り}");
}

