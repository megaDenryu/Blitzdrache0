//! 木の手順の組み手: 木の規則から手順を組み立てる途中の状態。種と指示の並びと選択の通し番号を持つ。
//!
//! 家の手順の組み手と分けるのは、積む相手の決め方が違うためである。家は直前に積んだ階の上へ積み、
//! 木は節ごとに番号を覚えて枝の親にする。共通なのは指示を積んで番号を数える規律であり、それは
//! `指示の並びの組み手`が持つ。
//!
//! 選択の通し番号を節ごとに1つ進めるのは、同じ種の木でも節ごとに違う生え口が選ばれるようにするためである。
//! 番号を進めないと、3節とも同じ方位の枝が出て、実データが3つの生え口を持つ意味が絵に出ない。

use super::super::part::部品ID;
use super::branch_choice::{節ごとの枝の候補, 節の枝};
use super::generation_seed::{展開の用途, 生成の種};
use super::instruction::{据えた部品の番号, 接合の指示};
use super::instruction_list_builder::指示の並びの組み手;
use super::tree_parts::{幹の指定, 枝の指定, 葉房の指定};
use crate::joint::{接合点名, 接合面上の位置, 法線方向のずらし};

pub(super) struct 木の手順の組み手 {
    種: 生成の種,
    並びの組み手: 指示の並びの組み手,
    選択の通し番号: u64,
}

impl 木の手順の組み手 {
    pub(super) fn 根の幹から始める(種: 生成の種) -> Self {
        Self {
            種,
            並びの組み手: 指示の並びの組み手::空から始める(),
            選択の通し番号: 0,
        }
    }

    /// 直前の節の頂部へ次の節を継ぎ、その節の番号を返す。一致の様式であるため、細くなる比は接合が導く。
    pub(super) fn 幹を1節継ぐ(&mut self, 幹: &幹の指定, 直前の節: 据えた部品の番号) -> 据えた部品の番号 {
        self.並びの組み手
            .接合を1つ積む(中心で継ぐ指示(直前の節, 幹.頂部.clone(), 幹.部品.clone(), 幹.基部.clone()))
    }

    /// 節1つぶんの枝と、その先の葉房を足す。候補が「生やさない」を選べば1つも積まない。
    pub(super) fn 節へ枝と葉房を足す(
        &mut self, 候補: &節ごとの枝の候補, 節の番号: 据えた部品の番号, 枝: &枝の指定, 葉房: &葉房の指定
    ) {
        let 値 = self
            .種
            .混合の生成器を作る()
            .零以上一未満(self.選択の通し番号, 展開の用途::節の枝の選択.番号());
        self.選択の通し番号 += 1;
        let 節の枝::生やす { 生え口 } = 候補.値から選ぶ(値) else {
            return;
        };
        let 枝の番号 = self
            .並びの組み手
            .接合を1つ積む(中心で継ぐ指示(節の番号, 生え口.clone(), 枝.部品.clone(), 枝.根元.clone()));
        self.並びの組み手.接合を1つ積む(中心で継ぐ指示(
            枝の番号,
            枝.頂芽.clone(),
            葉房.部品.clone(),
            葉房.枝の先へ付ける根元.clone(),
        ));
    }

    /// 幹の最上節の頂部へ葉房を継いで木の頂を塞ぐ。継がないと幹の切り口が絵に出る。
    pub(super) fn 冠を載せる(&mut self, 幹: &幹の指定, 最上節: 据えた部品の番号, 葉房: &葉房の指定) {
        self.並びの組み手.接合を1つ積む(中心で継ぐ指示(
            最上節,
            幹.頂部.clone(),
            葉房.部品.clone(),
            葉房.幹の頂へ付ける根元.clone(),
        ));
    }

    pub(super) fn 指示一覧へ畳む(self) -> Vec<接合の指示> {
        self.並びの組み手.指示一覧へ畳む()
    }
}

/// 面の中心で向かい合わせ、法線方向へ寄せない指示。木の接合はどれもこの形である。
/// 枝を食い込ませないのは、実データの生え口が幹の表面に在り、Blender側が食い込みを持たないためである。
fn 中心で継ぐ指示(
    親: 据えた部品の番号, 親の接合点: 接合点名, 子の部品: 部品ID, 子の接合点: 接合点名
) -> 接合の指示 {
    接合の指示 {
        親,
        親の接合点,
        子の部品,
        子の接合点,
        面上の位置: 接合面上の位置::中心(),
        法線方向のずらし: 法線方向のずらし::寄せない(),
    }
}
