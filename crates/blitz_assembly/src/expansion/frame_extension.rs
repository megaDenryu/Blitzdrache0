//! 骨格の継ぎ足し: 直前に据えた骨格へ骨格をもう1つ繋ぎ、その骨格が壁を受ける面を宣言する指定。
//!
//! **繋ぐ相手を「直前に据えた骨格」に固定し、番号で指させないのは、まだ据わっていない骨格を指す宣言を
//! 型で書けなくするためである。** 表せるのは連なりだけになるが、上へ積む骨組みも横へ継ぐ骨組みもどちらも連なりであり、
//! 枝分かれを要求する部品はまだ実物になっていない。
//!
//! 上へ積むか横へ継ぐかを枝で分けないのは、渡す接合点の名前が違うだけで、接合の計算も指示の形も同じだからである。
//! 骨格の上面と下面を渡せば上へ積み、右面と左面の継ぎ口を渡せば横へ継ぐ。どちらへ向かうかは接合点の宣言が決める。
//!
//! 食い込ませる量を宣言に持たせないのは、積層も継ぎも面が向かい合う隣接であり、重なる面をそもそも持たないためである。
//! 骨格の柱の外面が上下や左右へ連続するだけで、深度が競合する機構が無い。壁が0.02メートル食い込むのとは理由が違う。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格の上下積層とベイの継ぎ口(2026-08-19 追加)」

use crate::joint::接合点名;

use super::opening_choice::はめ口の指定;

#[derive(Debug, Clone, PartialEq)]
pub struct 骨格の継ぎ足し {
    直前の骨格の接合点: 接合点名,
    自分の接合点: 接合点名,
    はめ口一覧: Vec<はめ口の指定>,
}

impl 骨格の継ぎ足し {
    /// 破れうる前提を持たないため失敗しない。候補が空でないことは`はめ口の指定`が生成の時点で拒んでいる。
    pub fn 生成する(
        直前の骨格の接合点: 接合点名, 自分の接合点: 接合点名, はめ口一覧: Vec<はめ口の指定>
    ) -> Self {
        Self {
            直前の骨格の接合点,
            自分の接合点,
            はめ口一覧,
        }
    }

    pub(super) fn 直前の骨格の接合点(&self) -> &接合点名 {
        &self.直前の骨格の接合点
    }

    pub(super) fn 自分の接合点(&self) -> &接合点名 {
        &self.自分の接合点
    }

    /// この骨格が壁を受ける面。継いだ面のはめ口をここへ並べないことが、壁と隣の骨格が同じ面へ二重に入るのを防ぐ。
    /// **この排他は規則の責務であり、接合の契約は課さない。**
    pub(super) fn はめ口一覧(&self) -> &[はめ口の指定] {
        &self.はめ口一覧
    }
}
