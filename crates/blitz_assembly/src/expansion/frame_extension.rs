//! 骨格へ何を継ぎ足すかの候補と、その候補を並べた指定。直前に据えた骨格の1つの口へ、骨格をもう1つ継ぐか、
//! 屋根を載せるか、何も継がないかを種から選ぶ。
//!
//! **繋ぐ相手を「直前に据えた骨格」に固定し、番号で指させないのは、まだ据わっていない骨格を指す宣言を
//! 型で書けなくするためである。** 表せるのは連なりだけになるが、上へ積む骨組みも横へ継ぐ骨組みもどちらも連なりであり、
//! 枝分かれを要求する部品はまだ実物になっていない。
//!
//! 上へ積むか横へ継ぐかを枝で分けないのは、渡す接合点の名前が違うだけで、接合の計算も指示の形も同じだからである。
//! 骨格の上面と下面を渡せば上へ積み、右面と左面の継ぎ口を渡せば横へ継ぐ。屋根も同じ上面積層と下面積層の対で載る。
//!
//! 候補が空の指定を拒むのは、選べない選択肢が「選んだ結果が無い」という半端な状態を作るためである。
//! **「何も継がない」を表したいなら、それを候補の1つとして並べる。** 壁面の飾りとはめ口と節の枝と同じ様式である。
//!
//! 食い込ませる量を宣言に持たせないのは、積層も継ぎも面が向かい合う隣接であり、重なる面をそもそも持たないためである。
//! 骨格の柱の外面が上下や左右へ連続するだけで、深度が競合する機構が無い。壁が0.02メートル食い込むのとは理由が違う。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格の上下積層とベイの継ぎ口(2026-08-19 追加)」

use crate::joint::接合点名;

use super::super::part::部品ID;
use super::choice_index::添字へ写す;
use super::error_rule::規則エラー;
use super::opening_choice::はめ口の指定;

/// 継ぎ足しを1つ実行した結果、連なりをまだ伸ばせるか。**骨格を継いだときだけ伸ばせる。**
/// 屋根が宣言する接合点は下面積層1件だけであり、その上へ継げるものが無い。継ぎ足さない枝を引いたときも、
/// 新しく据わった骨格が無いため連なりを伸ばせない。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 連なりを伸ばせるか {
    伸ばせる,
    閉じた,
}

/// 直前に据えた骨格の1つの口へ継ぎ足すものの1つの候補。
#[derive(Debug, Clone, PartialEq)]
pub enum 骨格へ継ぎ足すもの {
    継ぎ足さない,
    /// 骨格をもう1つ継ぐ。**継いだ面のはめ口を並べないことが、壁と隣の骨格が同じ面へ二重に入るのを防ぐ。**
    /// この排他は規則の責務であり、接合の契約は課さない。
    骨格を継ぐ {
        自分の接合点: 接合点名,
        はめ口一覧: Vec<はめ口の指定>,
    },
    /// 骨格の上面へ屋根を載せる。屋根は接合点を下面積層1件しか持たないため、その上へ継げるものは無い。
    屋根を載せる {
        部品: 部品ID,
        下面: 接合点名,
    },
}

/// 直前に据えた骨格の1つの口と、そこへ継ぎ足す候補の並び。
#[derive(Debug, Clone, PartialEq)]
pub struct 継ぎ足しの指定 {
    直前の骨格の接合点: 接合点名,
    候補一覧: Vec<骨格へ継ぎ足すもの>,
}

impl 継ぎ足しの指定 {
    pub fn 生成する(直前の骨格の接合点: 接合点名, 候補一覧: Vec<骨格へ継ぎ足すもの>) -> Result<Self, 規則エラー> {
        if 候補一覧.is_empty() {
            return Err(規則エラー::継ぎ足しの候補が空である {
                直前の骨格の接合点の名前: 直前の骨格の接合点,
            });
        }
        Ok(Self {
            直前の骨格の接合点,
            候補一覧,
        })
    }

    pub(super) fn 直前の骨格の接合点(&self) -> &接合点名 {
        &self.直前の骨格の接合点
    }

    /// 0以上1未満の値から候補を1つ選ぶ。候補が空でないことを生成の時点で確かめてあるため、必ず1つ選べる。
    pub(super) fn 値から選ぶ(&self, 零以上一未満: f32) -> &骨格へ継ぎ足すもの {
        let 添字 = 添字へ写す(零以上一未満, self.候補一覧.len());
        match self.候補一覧.get(添字) {
            Some(候補) => 候補,
            None => panic!("候補が空でないという不変条件に違反した"),
        }
    }
}
