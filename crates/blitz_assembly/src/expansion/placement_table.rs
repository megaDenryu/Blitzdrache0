//! 部品ごとの配置表: 展開の結果。据えた順の並びを持ち、部品の種類ごとにまとめた眺めを答える。
//!
//! **部品ごとにまとめた眺めがそのまま描画対象の単位になる。** 100件ぶんの壁が1つの配置列に入ることで、
//! 発行数が件数に比例しなくなる。まとめた眺めの型は`per_part_placements`が持つ。
//!
//! 蓄えるのを据えた順にするのは、手順の指示が親を据えた番号で指し、検証の側が「何番目に据えた部品か」を
//! 必要とするためである。まとめた形だけを蓄えると、同じ部品が複数据わったときにどれが何番目かを取り出せない。
//! まとめる操作は蓄えた並びから毎回作る。据えた件数は高々数十であり、作り直す費用は問題にならない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「設計の核心」

use blitz_engine::個体配置;

use super::super::part::部品ID;
use super::per_part_placements::部品ごとの配置;

/// 据えた1件。どの部品がどこに置かれたかの組である。
#[derive(Debug, Clone, PartialEq)]
pub struct 据えた配置 {
    識別子: 部品ID,
    配置: 個体配置,
}

impl 据えた配置 {
    pub fn 識別子(&self) -> &部品ID {
        &self.識別子
    }

    pub fn 配置(&self) -> 個体配置 {
        self.配置
    }
}

#[derive(Debug, Clone, PartialEq)]
pub struct 部品ごとの配置表 {
    据えた順: Vec<据えた配置>,
}

impl 部品ごとの配置表 {
    pub(super) fn 空から始める() -> Self {
        Self { 据えた順: Vec::new() }
    }

    pub(super) fn 配置を1件足す(&mut self, 識別子: 部品ID, 配置: 個体配置) {
        self.据えた順.push(据えた配置 { 識別子, 配置 });
    }

    /// 据えた順の並び。手順の指示が指す番号と添字が一致する。
    pub fn 据えた順(&self) -> &[据えた配置] {
        &self.据えた順
    }

    /// 部品の種類ごとにまとめた眺め。並びは最初に据わった順である。**これが描画対象の単位になる。**
    pub fn 項目一覧(&self) -> Vec<部品ごとの配置> {
        let mut 一覧: Vec<部品ごとの配置> = Vec::new();
        for 据えた in &self.据えた順 {
            match 一覧.iter_mut().find(|項目| 項目.識別子() == 据えた.識別子()) {
                Some(項目) => 項目.配置を1件足す(据えた.配置()),
                None => {
                    let mut 項目 = 部品ごとの配置::識別子から空で始める(据えた.識別子().clone());
                    項目.配置を1件足す(据えた.配置());
                    一覧.push(項目);
                }
            }
        }
        一覧
    }

    /// 描画対象の数になる値。部品の種類数であり、据えた個体の数ではない。
    pub fn 部品の種類数(&self) -> usize {
        self.項目一覧().len()
    }

    pub fn 配置の総数(&self) -> usize {
        self.据えた順.len()
    }
}
