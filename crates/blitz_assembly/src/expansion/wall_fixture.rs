//! 規則の試験の材料。4つの壁面を持つ土台と、そこへ差し込む出窓のカタログを組む。
//!
//! 積層の試験の材料と分けているのは、壁面の接合点が天地を上に向けており、積層の接合点と姿勢の作り方が違うためである。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, 位置, 方向, 部品ローカル};

use crate::joint::{接合点, 接合点名, 接合種別, 接合面の姿勢, 接合面寸法};
use crate::part::{部品カタログ, 部品カタログ組み立て器, 部品定義};

use super::expansion_fixture::識別子;

/// 壁面の接合点。天地が上を向くため、積層の接合点と姿勢の作り方が違う。
pub(super) fn 壁の接合点を作る(名前: &str, 種別: 接合種別, 向き: [f32; 3], 面: [f32; 2]) -> 接合点 {
    let 姿勢 = 接合面の姿勢::生成する(方向::生成する(向き[0], 向き[1], 向き[2]).unwrap(), 方向::生成する(0.0, 1.0, 0.0).unwrap()).unwrap();
    接合点::生成する(
        接合点名::生成する(名前).unwrap(),
        種別,
        位置::<部品ローカル>::生成する(メートル::生成する(0.0), メートル::生成する(1.5), メートル::生成する(0.0)),
        姿勢,
        接合面寸法::生成する(メートル::生成する(面[0]), メートル::生成する(面[1])).unwrap(),
    )
}

/// 4つの壁面を持つ土台と、そこへ差し込む出窓のカタログ。規則の試験が使う。
pub(super) fn 出窓つきのカタログ() -> 部品カタログ {
    let 壁面 = |名前: &str, 向き: [f32; 3]| 壁の接合点を作る(名前, 接合種別::壁面取付, 向き, [6.0, 3.0]);
    let mut 組み立て器 = 部品カタログ組み立て器::空から始める();
    組み立て器
        .部品を1つ積む(
            識別子("土台"),
            部品定義::生成する(vec![
                壁面("正面壁", [0.0, 0.0, 1.0]),
                壁面("背面壁", [0.0, 0.0, -1.0]),
                壁面("左側面壁", [-1.0, 0.0, 0.0]),
                壁面("右側面壁", [1.0, 0.0, 0.0]),
            ])
            .unwrap(),
        )
        .unwrap();
    組み立て器
        .部品を1つ積む(
            識別子("出窓"),
            部品定義::生成する(vec![壁の接合点を作る("差込口", 接合種別::壁面差込, [0.0, 0.0, -1.0], [1.8, 1.4])]).unwrap(),
        )
        .unwrap();
    組み立て器.組み上げる().unwrap()
}
