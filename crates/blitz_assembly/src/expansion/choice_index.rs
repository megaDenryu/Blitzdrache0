//! 0以上1未満の値を候補の添字へ写す工程。受け取るのは混合が出した値と候補の件数、返すのは選ぶ添字である。
//!
//! 壁面の飾りと節の枝が同じ写し方を使うため、写しを持たずここが1つだけ持つ。写しを持つと、同じ種から
//! 違う候補が選ばれる形の食い違いが規則ごとに生まれる。
//!
//! 小数から整数への変換を持たないのは、標準ライブラリが型付きの変換を持たず、`as`による縮小変換を規約が禁じているためである。
//! 代わりに区間の上の境界と比べて進む。候補は高々数件であり、走査の費用は問題にならない。

/// 候補の件数で0以上1未満を等分し、値が入る区間の番号を返す。件数が0のときは0を返すが、
/// 候補が空でないことは候補を持つ型が生成の時点で拒むため、その値が使われることはない。
pub(super) fn 添字へ写す(零以上一未満: f32, 件数: usize) -> usize {
    let 件数の小数 = 小数へ写す(件数);
    let mut 添字 = 0;
    while 添字 + 1 < 件数 {
        let 上の境界 = 小数へ写す(添字 + 1) / 件数の小数;
        if 零以上一未満 < 上の境界 {
            break;
        }
        添字 += 1;
    }
    添字
}

fn 小数へ写す(値: usize) -> f32 {
    u16::try_from(値).map_or(f32::from(u16::MAX), f32::from)
}
