//! 一間四方の骨格の規則が組む姿の試験。担当するのは、決定性と、候補のどの枝も選ばれうることと、
//! 必ず入れる面を持つ規則では部品の種類数が種に依らないことを固定することである。
//!
//! 壁の姿勢の期待値は`frame_placement_tests`が持つ。確かめる軸が違い、材料の変わり方も違うためである。
//! こちらは候補の並べ方が動くと変わり、あちらは部品の接合点の宣言が動くと変わる。

#![allow(clippy::unwrap_used)]

use crate::joint::接合点名;

use super::error_rule::規則エラー;
use super::frame_fixture::識別子;
use super::frame_rule_fixture::{四面とも同じ候補の規則, 壁をはめる候補, 必ず三種が入る規則, 規則と種で展開する};
use super::opening_choice::{はめ口の指定, はめ口へ入れるもの};
use super::placement_table::部品ごとの配置表;
use super::rule::組み立て規則;

fn 件数を数える(配置表: &部品ごとの配置表, 綴り: &str) -> usize {
    配置表.据えた順().iter().filter(|据えた| 据えた.識別子() == &識別子(綴り)).count()
}

/// 平壁を入れるか入れないかの2択を4面へ置いた規則。候補の枝の選ばれ方を見る試験が使う。
fn 平壁を入れるか選ぶ規則() -> 組み立て規則 {
    四面とも同じ候補の規則(vec![はめ口へ入れるもの::入れない, 壁をはめる候補("平壁")])
}

/// 同じ種から2回展開すると、配置表が平行移動も回転も倍率も含めて完全に一致する。
#[test]
fn 同じ種からは同じ配置表が出る() {
    let 規則 = 平壁を入れるか選ぶ規則();
    assert_eq!(規則と種で展開する(&規則, 20260818), 規則と種で展開する(&規則, 20260818));
}

/// 候補の2つの枝がどちらも選ばれること。4面すべてに壁が入る種と1枚も入らない種の両方が出る。
#[test]
fn 候補のどの枝も選ばれうる() {
    let 規則 = 平壁を入れるか選ぶ規則();
    let 壁の件数: Vec<usize> = (1..60_u64).map(|種| 規則と種で展開する(&規則, 種).配置の総数() - 1).collect();
    assert!(壁の件数.contains(&0), "どの種でも壁が1枚以上入った。入れない枝が選ばれていない");
    assert!(
        壁の件数.contains(&4),
        "どの種でも4面すべてには入らなかった。はめる枝の選ばれ方が偏っている"
    );
}

/// **壁3種それぞれに必ず入れる面を割り当てると、部品の種類数が種に依らず4になる。**
/// 種類数が種で変わると、焼いた世界の描画発行数が種で変わり、件数に依らないことの実証が成り立たなくなる。
#[test]
fn 必ず入れる面を持つ規則では部品の種類数が種に依らない() {
    let 規則 = 必ず三種が入る規則();
    for 種 in 1..60_u64 {
        let 配置表 = 規則と種で展開する(&規則, 種);
        assert_eq!(配置表.部品の種類数(), 4, "種{種}での部品の種類数");
        assert_eq!(件数を数える(&配置表, "扉枠付きの壁"), 1, "種{種}での扉枠付きの壁の件数");
        assert!(件数を数える(&配置表, "窓壁") >= 1, "種{種}で窓壁が1枚も入らなかった");
        assert!(件数を数える(&配置表, "平壁") >= 1, "種{種}で平壁が1枚も入らなかった");
    }
}

/// 必ず入れる面を持つ規則でも、候補を持つ右面だけは種で変わる。壁の総数が4枚と5枚の両方が出ることが、
/// 選択がその面へ届いていることの証拠である。届いていなければ種類数の不変は自明に成り立ってしまう。
#[test]
fn 必ず入れる面を持つ規則でも候補を持つ面は種で変わる() {
    let 規則 = 必ず三種が入る規則();
    let 総数一覧: Vec<usize> = (1..60_u64).map(|種| 規則と種で展開する(&規則, 種).配置の総数()).collect();
    assert!(総数一覧.contains(&4), "右面へ何も入らない種が1つも無い");
    assert!(総数一覧.contains(&5), "右面へ壁が入る種が1つも無い");
}

/// 入れない枝だけを並べた候補では、骨格1件だけが据わる。壁が1枚も入らない形が組めることの確認である。
#[test]
fn 入れない枝だけの候補では骨格だけが据わる() {
    let 規則 = 四面とも同じ候補の規則(vec![はめ口へ入れるもの::入れない]);
    let 配置表 = 規則と種で展開する(&規則, 1);
    assert_eq!(配置表.配置の総数(), 1, "入れない枝しか無い規則で骨格以外が据わった");
    assert_eq!(配置表.部品の種類数(), 1);
}

/// 候補が空の指定を拒む。選べない選択肢は「選んだ結果が無い」という半端な状態を作る。
#[test]
fn 候補が空のはめ口の指定を拒む() {
    let 誤り = はめ口の指定::生成する(接合点名::生成する("正面のはめ口").unwrap(), Vec::new()).unwrap_err();
    assert!(matches!(誤り, 規則エラー::はめ口の候補が空である { .. }), "得た誤り: {誤り}");
}
