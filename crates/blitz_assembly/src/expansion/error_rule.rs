//! 規則が成り立たない事情。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。

use thiserror::Error;

use crate::joint::接合点名;

#[derive(Debug, Clone, PartialEq, Error)]
pub enum 規則エラー {
    #[error("壁面「{接合点の名前}」の候補が空である。何も付けない場合も候補の1つとして並べる")]
    壁面の候補が空である { 接合点の名前: 接合点名 },

    #[error("幹の節数が零である。根に据わる1節は必ずあるため、節数の下限は1である")]
    幹の節数が零である,

    #[error("幹の節の番号が零である。根の節を1として下から数える")]
    幹の節の番号が零である,

    #[error("枝を生やす節{節の番号}が幹の節数{幹の節数}を超える")]
    枝を生やす節が幹の節数を超える { 節の番号: usize, 幹の節数: usize },
}
