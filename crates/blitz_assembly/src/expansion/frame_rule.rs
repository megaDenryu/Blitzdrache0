//! 一間四方の骨格の規則: 骨格を連ねて据え、骨格ごとの4つのはめ口それぞれへ壁を1枚まで入れる規則。
//!
//! **規則は壁の位置も向きも、骨格を継ぐ方向も距離も持たない。** はめ口と継ぎ口と積層の口が面の位置と姿勢を
//! 宣言しており、壁がどの向きで立つかも隣の骨格がどこへ据わるかも接合が決める。4つのはめ口は向きだけが違い
//! 上方向はどれも天頂であるため、壁は天頂軸まわりに0度・90度・180度・270度だけ回る。
//!
//! 家の規則と分けるのは、枝の伸ばし方が違うためである。家は土台の上へ階を積んでから各階の壁面へ飾りを差し込む。
//! 骨格は骨格そのものを連ね、それぞれの空いた面へ壁をはめる。
//!
//! はめ口ごとに候補を1件引く形は、壁面の飾りと節の枝と同じ様式である。候補の数がそのまま割合を決める。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格と壁の対、扉の対」

use super::super::part::部品ID;
use super::frame_extension::骨格の継ぎ足し;
use super::frame_step_builder::一間四方の骨格の手順の組み手;
use super::generation_seed::生成の種;
use super::instruction::組み立て手順;
use super::opening_choice::はめ口の指定;

#[derive(Debug, Clone, PartialEq)]
pub struct 一間四方の骨格の規則 {
    骨格: 部品ID,
    根のはめ口一覧: Vec<はめ口の指定>,
    継ぎ足しの連なり: Vec<骨格の継ぎ足し>,
}

impl 一間四方の骨格の規則 {
    /// 破れうる前提を持たないため失敗しない。候補が空でないことは`はめ口の指定`が生成の時点で拒み、
    /// 継ぐ相手がまだ据わっていない宣言は`骨格の継ぎ足し`が連なりの形しか表せないことで拒んでいる。
    /// 連なりが空なら1ベイ1段である。
    pub fn 生成する(
        骨格: 部品ID, 根のはめ口一覧: Vec<はめ口の指定>, 継ぎ足しの連なり: Vec<骨格の継ぎ足し>
    ) -> Self {
        Self {
            骨格,
            根のはめ口一覧,
            継ぎ足しの連なり,
        }
    }

    /// 種から手順を生む。同じ種と同じ規則からは常に同じ手順が出る。
    pub(super) fn 種から手順を生む(&self, 種: 生成の種) -> 組み立て手順 {
        let mut 組み手 = 一間四方の骨格の手順の組み手::根の骨格から始める(種, self.骨格.clone());
        組み手.いま据わっている骨格のはめ口ごとに壁を1枚まで入れる(&self.根のはめ口一覧);
        for 継ぎ足し in &self.継ぎ足しの連なり {
            組み手.骨格をもう1つ継ぐ(継ぎ足し);
            組み手.いま据わっている骨格のはめ口ごとに壁を1枚まで入れる(継ぎ足し.はめ口一覧());
        }
        組み立て手順::根と指示から生成する(self.骨格.clone(), 組み手.指示一覧へ畳む())
    }
}
