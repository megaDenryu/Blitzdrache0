//! 展開を進められない事情。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! 指示の添字を持つのは、手順のどこで止まったかが分からないと読み手が直す先を決められないためである。

use thiserror::Error;

use crate::joint::接合点名;
use crate::mating::接合エラー;

use super::super::part::部品ID;

#[derive(Debug, Clone, PartialEq, Error)]
pub enum 展開エラー {
    #[error("部品{部品の識別子}がカタログに無い")]
    部品がカタログに無い { 部品の識別子: 部品ID },

    #[error("部品{部品の識別子}に接合点「{接合点の名前}」が無い")]
    接合点が部品に無い {
        部品の識別子: 部品ID, 接合点の名前: 接合点名
    },

    #[error("指示[{指示の添字}]が指す親の番号{親の番号}は、まだ据わっていない(据えた件数は{据えた件数})")]
    親がまだ据わっていない {
        指示の添字: usize, 親の番号: usize, 据えた件数: usize
    },

    #[error("指示[{指示の添字}]の接合を組めない: {誤り}")]
    接合を組めない {
        指示の添字: usize,
        #[source]
        誤り: 接合エラー,
    },
}
