//! 壁の外面の飾りの試験の材料。飾りを引く壁の候補と、出窓の候補と、飾りを持つ2つの規則を持つ。
//! 飾りを持たない壁の候補と1ベイ1段の規則は`frame_rule_fixture`が持つ。
//!
//! 飾りだけを別の材料にするのは、確かめる軸が違うためである。あちらは壁が面ごとに選ばれることを見る。
//! こちらは据えた壁の外面へ飾りが継がることを見る。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use crate::joint::法線方向のずらし;

use super::super::frame_floor::骨格へ張る床;
use super::super::frame_ornament::{壁の外面の飾り, 壁の外面の飾りの指定};
use super::super::frame_rule::一間四方の骨格の規則;
use super::super::opening_choice::{はめ口の指定, はめ口へ入れるもの};
use super::super::ornament_stack::飾りの上へ積み足す部品;
use super::super::rule::組み立て規則;
use super::frame_bay_joint_fixture::はめ口の宣言一覧;
use super::frame_fixture::{名前, 識別子, 骨格の部品};
use super::frame_rule_fixture::食い込ませる量;

/// 背面のはめ口の綴り。飾りを1面だけへ付ける規則が名指す。
const 背面のはめ口: &str = "背面のはめ口";

/// 外面の飾りの候補を名指した壁の候補。**飾りの選択が壁の候補に属することを、この口の形が示す。**
pub(super) fn 外面へ飾りを引く壁の候補(綴り: &str, 飾りの候補一覧: Vec<壁の外面の飾り>) -> はめ口へ入れるもの {
    はめ口へ入れるもの::壁をはめる {
        部品: 識別子(綴り),
        外枠: 名前("壁の外枠"),
        法線方向のずらし: 食い込ませる量(),
        外面の飾り: 壁の外面の飾りの指定::生成する(名前("外面の飾り取付"), 飾りの候補一覧).unwrap(),
    }
}

/// 壁の外面へ出窓を差し込む候補。出窓の差込口は壁の取付面へ寄せずに向かい合う。**出窓は葉であり、
/// 上へ積み足すものを1件も持たない。**
pub(super) fn 出窓を差し込む候補() -> 壁の外面の飾り {
    壁の外面の飾り::差し込む {
        部品: 識別子("出窓"),
        差込口: 名前("壁面差込口"),
        法線方向のずらし: 法線方向のずらし::寄せない(),
        上へ積み足すもの一覧: Vec::new(),
    }
}

/// 壁の外面へ煙突の1段目を差し込み、その上へ名指した段数だけ同じ部品を積み足す候補。
/// **飾りが葉でなくなる初めての形であり、据わる段数は積み足すものの並びの長さが決める。**
pub(super) fn 煙突を立てる候補(上へ積み足す段数: usize) -> 壁の外面の飾り {
    壁の外面の飾り::差し込む {
        部品: 識別子("煙突"),
        差込口: 名前("壁面密着面"),
        法線方向のずらし: 法線方向のずらし::寄せない(),
        上へ積み足すもの一覧: (0..上へ積み足す段数).map(|_| 煙突を1段積み足す()).collect(),
    }
}

fn 煙突を1段積み足す() -> 飾りの上へ積み足す部品 {
    飾りの上へ積み足す部品::生成する(名前("上面"), 識別子("煙突"), 名前("下面"), 法線方向のずらし::寄せない())
}

/// 4面へ平壁を入れ、背面の壁だけが必ず出窓を差し込む規則。飾りの位置を見る試験が使う。
pub(super) fn 背面へ必ず出窓を差し込む規則() -> 組み立て規則 {
    背面の飾りの候補で規則を組む(vec![出窓を差し込む候補()])
}

/// 4面へ平壁を入れ、背面の壁だけが必ず煙突を立てる規則。名指した段数だけ1段目の上へ積み足す。
pub(super) fn 背面へ必ず煙突を立てる規則(上へ積み足す段数: usize) -> 組み立て規則 {
    背面の飾りの候補で規則を組む(vec![煙突を立てる候補(上へ積み足す段数)])
}

/// 背面の壁の飾りが「付けない」と「出窓」の2択である規則。どちらの枝も選ばれうることを見る試験が使う。
pub(super) fn 背面の飾りが二択の規則() -> 組み立て規則 {
    背面の飾りの候補で規則を組む(vec![壁の外面の飾り::付けない, 出窓を差し込む候補()])
}

/// 背面の面だけへ壁を入れ、その壁の外面の飾りを名指した候補から引く規則。
/// 1面だけにするのは、4面すべてが飾りを引くと据わった飾りがどの壁のものか数から言えなくなるためである。
fn 背面の飾りの候補で規則を組む(飾りの候補一覧: Vec<壁の外面の飾り>) -> 組み立て規則 {
    let はめ口一覧 = はめ口の宣言一覧
        .into_iter()
        .map(|(綴り, _)| {
            let 候補 = if 綴り == 背面のはめ口 {
                外面へ飾りを引く壁の候補("平壁", 飾りの候補一覧.clone())
            } else {
                外面へ飾りを引く壁の候補("平壁", vec![壁の外面の飾り::付けない])
            };
            はめ口の指定::生成する(名前(綴り), vec![候補]).unwrap()
        })
        .collect();
    組み立て規則::一間四方の骨格(一間四方の骨格の規則::生成する(
        骨格の部品(),
        骨格へ張る床::張らない,
        はめ口一覧,
        Vec::new(),
    ))
}
