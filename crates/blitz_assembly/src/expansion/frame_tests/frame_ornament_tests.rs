//! 壁の外面へ飾りを差し込んだ組み立ての試験。担当するのは、飾りが据わる位置と枚数と、飾りの候補のどちらの枝も
//! 選ばれうることと、壁の入らない面へ飾りが付かないことを固定することである。
//!
//! **期待値は接合点の宣言から手で当てた値である。** 噛み合わせそのものの導出は
//! `mating::oriel_placement_tests`が持つ。背面の壁は`[0,0,-0.98]`へ回らずに据わり、その外面の飾り取付は
//! 壁ローカルの`[0,1.3,-0.2]`にある。出窓の差込口は向きも上方向も取付面と同じであるため天頂軸まわりに
//! 180度回り、`[0,0.7,-0.4]`が`[0,0.7,0.4]`になって、出窓の原点が`[0,0.6,-1.58]`へ据わる。
//! **この数は規則にも手順にも書かれていない。**

#![allow(clippy::unwrap_used)]

use crate::joint::接合点名;

use super::super::error_rule::規則エラー;
use super::super::frame_ornament::壁の外面の飾りの指定;
use super::frame_chain_fixture::{平行移動が近いか, 綴りごとの配置};
use super::frame_ornament_fixture::{背面の飾りが二択の規則, 背面へ必ず出窓を差し込む規則};
use super::frame_rule_fixture::規則と種で展開する;

/// 出窓の部品の綴り。試験が飾りの件数を数えるために使う。
const 出窓の綴り: &str = "出窓";

/// 背面の壁の外面へ出窓が1件だけ、天頂軸まわりに180度回して据わる。
#[test]
fn 出窓が背面の壁の外面へ回して据わる() {
    let 出窓一覧 = 綴りごとの配置(&規則と種で展開する(&背面へ必ず出窓を差し込む規則(), 1), 出窓の綴り);
    assert_eq!(出窓一覧.len(), 1, "出窓が1件据わっていない");
    assert!(
        平行移動が近いか(出窓一覧[0].平行移動(), [0.0, 0.6, -1.58]),
        "得た平行移動: {:?}",
        出窓一覧[0].平行移動()
    );
    assert!(
        (出窓一覧[0].回転()[1].abs() - 1.0).abs() < 1.0e-5,
        "天頂軸まわりの半回転になっていない: {:?}",
        出窓一覧[0].回転()
    );
}

/// 飾りの候補のどちらの枝も選ばれうる。付けないを引いた種では飾りが1件も据わらない。
#[test]
fn 飾りの候補のどちらの枝も選ばれうる() {
    let 規則 = 背面の飾りが二択の規則();
    let 件数一覧: Vec<usize> = (1..60_u64)
        .map(|種| 綴りごとの配置(&規則と種で展開する(&規則, 種), 出窓の綴り).len())
        .collect();
    assert!(件数一覧.contains(&1), "出窓が据わる種が1つも無い");
    assert!(件数一覧.contains(&0), "出窓が据わらない種が1つも無い");
}

/// 飾りの選択は壁の候補に属するため、壁の入らない面へ飾りだけが浮くことは起こりえない。
/// **入れない候補だけを並べた規則では、飾りの候補が出窓だけであっても出窓は1件も据わらない。**
#[test]
fn 壁の入らない面へ飾りは付かない() {
    let 規則 = 壁を入れない規則();
    for 種 in 1..30_u64 {
        assert!(
            綴りごとの配置(&規則と種で展開する(&規則, 種), 出窓の綴り).is_empty(),
            "種{種}で壁の無い面へ飾りが据わった"
        );
    }
}

/// 候補が空の飾りの指定を拒む。選べない選択肢は「選んだ結果が無い」という半端な状態を作る。
#[test]
fn 候補が空の飾りの指定を拒む() {
    let 誤り = 壁の外面の飾りの指定::生成する(接合点名::生成する("外面の飾り取付").unwrap(), Vec::new()).unwrap_err();
    assert!(matches!(誤り, 規則エラー::壁の外面の飾りの候補が空である { .. }), "得た誤り: {誤り}");
}

