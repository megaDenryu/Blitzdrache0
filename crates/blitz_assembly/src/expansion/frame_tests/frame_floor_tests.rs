//! 骨格へ床を張った組み立ての試験。担当するのは、床が張られる高さと枚数と、床を宣言しない規則が床を1枚も
//! 出さないことを固定することである。噛み合わせそのものの予測値は`mating::floor_placement_tests`が持つ。
//!
//! **期待値は接合点の宣言から手で当てた値である。** 骨格の床のはめ口は部品ローカルの高さ0.16メートル(土台の梁の
//! 上面)にあり、床板の外枠は部品の原点にあるため、床板の原点は0.16へ据わる。2階の骨格は階高2.60だけ上に
//! 据わるため、2階の床は2.76になる。**どちらの数も規則には1つも書かれていない。**
//!
//! 床の枚数を数えるのは、床が骨格ごとに1枚であることを固定するためである。骨格を据えたら必ず床という形にすると、
//! 骨格の継ぎ方だけを見る見本の世界にも床が入り、Blender側の正解表と食い違う。

#![allow(clippy::unwrap_used)]

use super::frame_chain_fixture::{平行移動が近いか, 床板の綴り, 恒等の姿勢か, 綴りごとの配置, 骨格の綴り};
use super::frame_chain_rule_fixture::{
    二段に積んだ骨格の規則, 屋根を載せた一間四方の家の規則, 屋根を載せた二段の家の規則
};
use super::frame_rule_fixture::規則と種で展開する;

/// 骨格が宣言する床のはめ口の高さ。土台の梁の上面である。
const 床のはめ口の高さメートル: f32 = 0.16;

/// 階高。骨格の上面の接合点の高さそのものである。
const 階高メートル: f32 = 2.6;

/// 1ベイの家の床が土台の梁の上面の高さへ、回らずに1枚だけ据わる。
#[test]
fn 一間四方の家の床が土台の梁の上面の高さへ据わる() {
    let 床一覧 = 綴りごとの配置(&規則と種で展開する(&屋根を載せた一間四方の家の規則(), 1), 床板の綴り);
    assert_eq!(床一覧.len(), 1, "床が1枚据わっていない");
    assert!(
        平行移動が近いか(床一覧[0].平行移動(), [0.0, 床のはめ口の高さメートル, 0.0]),
        "得た平行移動: {:?}",
        床一覧[0].平行移動()
    );
    assert!(恒等の姿勢か(床一覧[0].回転()), "得た回転: {:?}", 床一覧[0].回転());
}

/// 2段の家の床が階ごとに1枚ずつ、それぞれの骨格の床のはめ口の高さへ据わる。
/// **2階の床の高さが階高と床のはめ口の高さの和になることが、床にもY成分の累和が効くことの証拠である。**
#[test]
fn 二段の家の床が階ごとに一枚ずつ据わる() {
    let 配置表 = 規則と種で展開する(&屋根を載せた二段の家の規則(), 1);
    let 床一覧 = 綴りごとの配置(&配置表, 床板の綴り);
    assert_eq!(綴りごとの配置(&配置表, 骨格の綴り).len(), 2, "骨格が2件据わっていない");
    assert_eq!(床一覧.len(), 2, "床が2枚据わっていない");
    assert!(平行移動が近いか(床一覧[0].平行移動(), [0.0, 床のはめ口の高さメートル, 0.0]));
    assert!(
        平行移動が近いか(床一覧[1].平行移動(), [0.0, 階高メートル + 床のはめ口の高さメートル, 0.0]),
        "得た平行移動: {:?}",
        床一覧[1].平行移動()
    );
}

/// 床を宣言しない規則では床が1枚も据わらない。**骨格が床のはめ口を宣言していることは、床が必ず入ることを意味しない。**
/// この道が破れると、骨格の継ぎ方だけを見る見本の世界へ床が紛れ込む。
#[test]
fn 床を宣言しない規則では床が一枚も据わらない() {
    let 配置表 = 規則と種で展開する(&二段に積んだ骨格の規則(), 1);
    assert_eq!(綴りごとの配置(&配置表, 骨格の綴り).len(), 2, "骨格が2件据わっていない");
    assert!(綴りごとの配置(&配置表, 床板の綴り).is_empty(), "床を宣言していないのに床が据わった");
}
