//! 壁の外面へ立てた煙突の組み立ての試験。担当するのは、飾りの上へ積み足すものの並びの長さがそのまま据わる段数に
//! なることと、次の段が直前の段の上面の高さへ載ることを固定することである。
//!
//! 飾りの試験(`frame_ornament_tests`)から分けるのは、確かめる軸が違うためである。あちらは壁が飾りを1つ受ける
//! ことと候補のどちらの枝も選ばれうることを見る。こちらは据えた飾りがさらに部品を受けて連なりが伸びることを見る。
//!
//! **期待値は接合点の宣言から手で当てた値である。** 噛み合わせそのものの導出は`mating::chimney_placement_tests`が
//! 持つ。ここが確かめるのは、規則の宣言した段数だけ指示が出て、親が直前に据えた段になっていることである。
//! 煙突の上面の接合点は高さ2.60メートルにあり、**この数は規則にも試験にも書かれていない。**

#![allow(clippy::unwrap_used)]

use blitz_engine::個体配置;

use super::frame_chain_fixture::{平行移動が近いか, 綴りごとの配置};
use super::frame_chimney_joint_fixture::煙突の一段の丈;
use super::frame_ornament_fixture::背面へ必ず煙突を立てる規則;
use super::frame_rule_fixture::規則と種で展開する;

/// 煙突の部品の綴り。試験が段数を数えるために使う。
const 煙突の綴り: &str = "煙突";

/// 積み足すものを1件も持たない煙突は、壁へ差し込んだ1段目だけで終わる。
#[test]
fn 積み足すものが空なら煙突は一段で終わる() {
    assert_eq!(煙突の配置一覧(0).len(), 1, "積み足すものが空なのに2段目が据わった");
}

/// 積み足すものを1件持つ煙突は2段になり、2段目が1段目の真上へ1段ぶんの丈だけ高く据わる。
#[test]
fn 煙突の二段目が一段目の上面の高さへ載る() {
    let 二段 = 煙突の配置一覧(1);
    assert_eq!(二段.len(), 2, "2段目が据わっていない");
    let 高さの差 = 二段[1].平行移動()[1] - 二段[0].平行移動()[1];
    assert!((高さの差 - 煙突の一段の丈).abs() < 1.0e-5, "得た高さの差: {高さの差}");
    assert!(
        平行移動が近いか(二段[1].平行移動(), 一段目の真上(二段[0].平行移動())),
        "2段目が1段目の真上に無い"
    );
}

/// 背面の壁へ煙突を立て、名指した段数だけ積み足した配置。並びは据えた順であるため下から上へ並ぶ。
fn 煙突の配置一覧(上へ積み足す段数: usize) -> Vec<個体配置> {
    let 規則 = 背面へ必ず煙突を立てる規則(上へ積み足す段数);
    綴りごとの配置(&規則と種で展開する(&規則, 1), 煙突の綴り)
}

/// 名指した平行移動の真上、1段ぶんの丈だけ高い位置。
fn 一段目の真上(一段目の平行移動: [f32; 3]) -> [f32; 3] {
    [一段目の平行移動[0], 一段目の平行移動[1] + 煙突の一段の丈, 一段目の平行移動[2]]
}
