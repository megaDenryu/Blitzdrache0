//! ベイ格子から作った手順と、骨格を連ねる規則から作った手順が、同じ形の建物について同じ配置表になることの試験。
//!
//! 骨格方式の試験の束に置くのは、展開に要るカタログと規則の材料がここにあるためである。格子の側の試験
//! (`crates/blitz_assembly/src/building_grid/grid_recipe_tests.rs`)は指示の姿だけを見て、据わる位置は見ない。
//!
//! 位置の期待値を新しく書き下ろさず既存の規則と突き合わせるのは、規則の側が正解表との突き合わせを済ませて
//! いるためである。**格子が規則と同じ配置表を出すなら、格子も同じ正解表に合っている。**

#![allow(clippy::unwrap_used)]

use crate::building_grid::grid_fixture::{
    升目の並びから格子を組む, 右面を空けた升目, 四面へ平壁を入れた升目, 左面を空けた升目
};
use crate::building_grid::{升目の屋根, 升目の床, 升目の座標};

use super::bay_grid_agreement_fixture::{
    壁三種を入れた升目, 格子を展開する, 突き合わせに使う種, 面ごとに壁を割り当てた規則
};
use super::frame_chain_rule_fixture::{
    二段に積んだ骨格の規則, 屋根を載せた一間四方の家の規則, 屋根を載せた二段の家の規則, 横に二ベイ継いだ骨格の規則,
};
use super::frame_rule_fixture::規則と種で展開する;

#[test]
fn 壁三種を入れた一升目が規則と同じ配置表になる() {
    let 格子 = 升目の並びから格子を組む(&[(升目の座標::生成する(0, 0, 0), 壁三種を入れた升目())]);
    let 規則 = 面ごとに壁を割り当てた規則([
        ("正面のはめ口", "扉枠付きの壁"),
        ("背面のはめ口", "平壁"),
        ("左面のはめ口", "窓壁"),
        ("右面のはめ口", "平壁"),
    ]);
    assert_eq!(格子を展開する(&格子), 規則と種で展開する(&規則, 突き合わせに使う種));
}

#[test]
fn 二段に積んだ格子が規則と同じ配置表になる() {
    let 格子 = 升目の並びから格子を組む(&[
        (升目の座標::生成する(0, 0, 0), 四面へ平壁を入れた升目()),
        (升目の座標::生成する(0, 0, 1), 四面へ平壁を入れた升目()),
    ]);
    assert_eq!(格子を展開する(&格子), 規則と種で展開する(&二段に積んだ骨格の規則(), 突き合わせに使う種));
}

#[test]
fn 横に二ベイ継いだ格子が規則と同じ配置表になる() {
    let 格子 = 升目の並びから格子を組む(&[
        (升目の座標::生成する(0, 0, 0), 右面を空けた升目()),
        (升目の座標::生成する(1, 0, 0), 左面を空けた升目()),
    ]);
    assert_eq!(
        格子を展開する(&格子),
        規則と種で展開する(&横に二ベイ継いだ骨格の規則(), 突き合わせに使う種)
    );
}

#[test]
fn 床と屋根を持つ一升目が規則と同じ配置表になる() {
    let 升目 = 四面へ平壁を入れた升目().床を定める(升目の床::張る).屋根を定める(升目の屋根::載せる);
    let 格子 = 升目の並びから格子を組む(&[(升目の座標::生成する(0, 0, 0), 升目)]);
    assert_eq!(
        格子を展開する(&格子),
        規則と種で展開する(&屋根を載せた一間四方の家の規則(), 突き合わせに使う種)
    );
}

#[test]
fn 床と屋根を持つ二段の格子が規則と同じ配置表になる() {
    let 格子 = 升目の並びから格子を組む(&[
        (升目の座標::生成する(0, 0, 0), 四面へ平壁を入れた升目().床を定める(升目の床::張る)),
        (
            升目の座標::生成する(0, 0, 1),
            四面へ平壁を入れた升目().床を定める(升目の床::張る).屋根を定める(升目の屋根::載せる),
        ),
    ]);
    assert_eq!(
        格子を展開する(&格子),
        規則と種で展開する(&屋根を載せた二段の家の規則(), 突き合わせに使う種)
    );
}

/// 同じ格子から2回展開すると、配置表が平行移動も回転も倍率も含めて完全に一致する。
#[test]
fn 同じ格子からは同じ配置表が出る() {
    let 格子 = 升目の並びから格子を組む(&[
        (升目の座標::生成する(0, 0, 0), 四面へ平壁を入れた升目().床を定める(升目の床::張る)),
        (升目の座標::生成する(0, 0, 1), 四面へ平壁を入れた升目().屋根を定める(升目の屋根::載せる)),
    ]);
    assert_eq!(格子を展開する(&格子), 格子を展開する(&格子));
}
