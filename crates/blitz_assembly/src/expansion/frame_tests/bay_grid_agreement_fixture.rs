//! ベイ格子と規則の突き合わせの試験の材料。格子を展開する口と、面ごとに壁を割り当てた1ベイ1段の規則と、
//! 壁3種を面ごとに入れた升目を持つ。突き合わせそのものは`bay_grid_agreement_tests`が持つ。
//!
//! 材料を分けるのは、変わる理由が違うためである。展開の口は配置表の作り方が変わると変わり、
//! 突き合わせの並びは確かめる建物の形を増やすと変わる。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use crate::building_grid::grid_fixture::{試験の部品の綴り, 飾りを付けない壁};
use crate::building_grid::{ベイ格子, 升目の側面, 升目の宣言, 壁の種類};

use super::super::expander::展開器;
use super::super::frame_floor::骨格へ張る床;
use super::super::frame_rule::一間四方の骨格の規則;
use super::super::opening_choice::はめ口の指定;
use super::super::placement_table::部品ごとの配置表;
use super::super::rule::組み立て規則;
use super::frame_fixture::{一間四方の骨格のカタログ, 名前, 骨格の部品};
use super::frame_rule_fixture::{原点の配置, 壁をはめる候補};

/// 候補を1つに固定した規則と突き合わせるため、どの種でも同じ組み立てが出る。
pub(super) const 突き合わせに使う種: u64 = 1;

pub(super) fn 格子を展開する(格子: &ベイ格子) -> 部品ごとの配置表 {
    let 手順 = 格子.組み立て手順へ写す(&試験の部品の綴り());
    展開器::カタログを持たせて生成する(一間四方の骨格のカタログ())
        .手順を展開する(&手順, 原点の配置())
        .unwrap()
}

/// 面ごとに1種類の壁を必ず入れる1ベイ1段の規則。面の綴りと壁の綴りの対を並べた順が、はめ口を見る順になる。
pub(super) fn 面ごとに壁を割り当てた規則(割り当て一覧: [(&str, &str); 4]) -> 組み立て規則 {
    let はめ口一覧 = 割り当て一覧
        .into_iter()
        .map(|(面の綴り, 壁の綴り)| はめ口の指定::生成する(名前(面の綴り), vec![壁をはめる候補(壁の綴り)]).unwrap())
        .collect();
    組み立て規則::一間四方の骨格(一間四方の骨格の規則::生成する(
        骨格の部品(),
        骨格へ張る床::張らない,
        はめ口一覧,
        Vec::new(),
    ))
}

/// 壁3種を面ごとに割り当てた升目。扉枠付きの壁1枚・窓壁1枚・平壁2枚である。
pub(super) fn 壁三種を入れた升目() -> 升目の宣言 {
    升目の宣言::骨格だけを置く()
        .側面を定める(升目の側面::正面, 飾りを付けない壁(壁の種類::扉枠付きの壁))
        .側面を定める(升目の側面::背面, 飾りを付けない壁(壁の種類::平壁))
        .側面を定める(升目の側面::左面, 飾りを付けない壁(壁の種類::窓壁))
        .側面を定める(升目の側面::右面, 飾りを付けない壁(壁の種類::平壁))
}
