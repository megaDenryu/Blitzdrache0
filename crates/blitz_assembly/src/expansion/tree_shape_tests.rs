//! 木の規則が組む姿の試験。担当するのは、1本の木が幹と枝と葉房と冠になることと、部品の員数が
//! 規則の候補の引き方から決まることと、同じ種からの2回の展開が完全に一致することを固定することである。
//!
//! 倍率と高さの試験は`tree_scale_tests`が持つ。確かめる軸が違い、材料の変わり方も違うためである。
//! こちらは部品の員数が動くと変わり、あちらは部品の寸法が動くと変わる。

#![allow(clippy::unwrap_used)]

use crate::tree_catalog_fixture::{樫の木のカタログ, 識別子};

use super::expander::展開器;
use super::generation_seed::生成の種;
use super::placement_table::部品ごとの配置表;
use super::tree_rule_fixture::{
    枝を出さない候補, 根の配置, 樫の木の規則, 樫の木を展開する, 種を決めて樫の木を展開する
};

fn 件数を数える(配置表: &部品ごとの配置表, 綴り: &str) -> usize {
    配置表.据えた順().iter().filter(|据えた| 据えた.識別子() == &識別子(綴り)).count()
}

/// 幹3節・節ごとの枝3本・その先の葉房3つ・幹の頂を塞ぐ冠1つで10部品になる。
#[test]
fn 一本の木は幹と枝と葉房と冠になる() {
    let 配置表 = 樫の木を展開する(3);
    assert_eq!(配置表.配置の総数(), 10);
    assert_eq!(配置表.部品の種類数(), 3);
    assert_eq!(件数を数える(&配置表, "幹の一節"), 3);
    assert_eq!(件数を数える(&配置表, "大枝"), 3);
    assert_eq!(件数を数える(&配置表, "葉房"), 4);
}

/// **葉房が付くのは枝の先と幹の頂だけである。** 枝1本につき1つと、木の頂に1つで、枝の数より必ず1つ多い。
#[test]
fn 葉房は枝の先と冠にだけ付く() {
    for 節数 in [1_usize, 2, 3, 5] {
        let 配置表 = 樫の木を展開する(節数);
        let (枝, 葉房) = (件数を数える(&配置表, "大枝"), 件数を数える(&配置表, "葉房"));
        assert_eq!(葉房, 枝 + 1, "{節数}節の木の枝{枝}本に対する葉房{葉房}件");
    }
}

/// **枝の本数は幹の節数を超えない。** 節ごとに候補を1件引く形であるため、節を名指しする規則が持っていた
/// 「幹より高い節を指す」誤りが構造的に起きない。
#[test]
fn 枝の本数は幹の節数を超えない() {
    for 節数 in [1_usize, 2, 3, 5] {
        let 配置表 = 樫の木を展開する(節数);
        assert!(件数を数える(&配置表, "大枝") <= 節数, "{節数}節の木の枝の本数");
    }
}

/// 候補が生やさない枝だけなら、木は幹と冠だけになる。候補の並びが枝の本数を決めることの対照である。
#[test]
fn 生やさない候補だけなら幹と冠だけになる() {
    let 規則 = 樫の木の規則(3, 枝を出さない候補());
    let 配置表 = 展開器::カタログを持たせて生成する(樫の木のカタログ())
        .規則から展開する(&規則, 生成の種::値から生成する(7), 根の配置())
        .unwrap();
    assert_eq!(件数を数える(&配置表, "大枝"), 0);
    assert_eq!(件数を数える(&配置表, "葉房"), 1);
    assert_eq!(配置表.配置の総数(), 4);
}

/// 生え口が3つ在る意味は、種を変えると枝の向きが変わることである。種だけを変えて配置表が動くことを見る。
#[test]
fn 種を変えると枝の姿勢が変わる() {
    let 一つ目 = 種を決めて樫の木を展開する(3, 7);
    let 別の種 = (1..64).map(|値| 種を決めて樫の木を展開する(3, 値)).find(|配置表| 配置表 != &一つ目);
    assert!(別の種.is_some(), "64通りの種のどれもが同じ配置表を出した");
}

/// 平行移動も回転も倍率も含めて一致することを見る。平行移動だけを比べると、回転だけが揺れる形の破れを見逃す。
/// 綴りをバイトで比べるのは、値の等しさの判定が零の符号違いを同じものとして扱うためである。
#[test]
fn 同じ規則からの2回の展開は綴りまで完全に一致する() {
    let (一回目, 二回目) = (樫の木を展開する(3), 樫の木を展開する(3));
    assert_eq!(一回目, 二回目);
    assert_eq!(format!("{一回目:?}").as_bytes(), format!("{二回目:?}").as_bytes());
}
