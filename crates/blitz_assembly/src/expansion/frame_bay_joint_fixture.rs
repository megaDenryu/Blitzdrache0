//! 一間四方の骨格が宣言する接合点11件の試験の材料。骨格へ取り付く部品の接合点は`frame_attached_joint_fixture`が、
//! カタログの組み立ては`frame_fixture`が持つ。
//!
//! 値は`Mod_Frame_Bay_Single`のextrasから読んだ実物であり、雛形ではない。はめ口4件・ベイの継ぎ口4件・
//! 骨格の上面と下面の2件・床のはめ口1件である。
//!
//! **はめ口と継ぎ口は同じ位置・同じ姿勢・同じ寸法で重ねて宣言されている。** 同じ物理面が「壁を受ける口」と
//! 「隣のベイを継ぐ口」の2つの意味を持ち、どちらか一方だけを使う。この排他は規則の責務であり、接合の契約は課さない。
//!
//! 上下の積層の口と床のはめ口だけ上方向が天頂でなく奥行方向であるのは、面そのものが水平を向いているためである。
//! 水平な面の縦軸を天頂に取ることはできない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格の上下積層とベイの継ぎ口(2026-08-19 追加)」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, 位置, 方向, 部品ローカル};

use crate::joint::{接合点, 接合点名, 接合種別, 接合面の姿勢, 接合面の形と寸法};

/// 骨格の4つのはめ口。名前と外向き法線の組であり、面の中心は法線の向きへ1.0メートル進んだ位置にある。
pub(super) const はめ口の宣言一覧: [(&str, [f32; 3]); 4] = [
    ("正面のはめ口", [0.0, 0.0, 1.0]),
    ("背面のはめ口", [0.0, 0.0, -1.0]),
    ("左面のはめ口", [-1.0, 0.0, 0.0]),
    ("右面のはめ口", [1.0, 0.0, 0.0]),
];

/// 骨格の4つのベイの継ぎ口。はめ口とまったく同じ面へ重ねて宣言されている。
pub(super) const 継ぎ口の宣言一覧: [(&str, [f32; 3]); 4] = [
    ("正面の継ぎ口", [0.0, 0.0, 1.0]),
    ("背面の継ぎ口", [0.0, 0.0, -1.0]),
    ("左面の継ぎ口", [-1.0, 0.0, 0.0]),
    ("右面の継ぎ口", [1.0, 0.0, 0.0]),
];

pub(super) const 骨格の上面の名前: &str = "骨格の上面";
pub(super) const 骨格の下面の名前: &str = "骨格の下面";
/// 骨格が土台の梁の上面(高さ0.16メートル)へ宣言する、床板を受ける口。
pub(super) const 床のはめ口の名前: &str = "床のはめ口";

pub(super) fn 骨格の接合点一覧() -> Vec<接合点> {
    let mut 一覧: Vec<接合点> = はめ口の宣言一覧
        .into_iter()
        .map(|(名前, 法線)| 側面の接合点(名前, 接合種別::壁のはめ口, 法線))
        .collect();
    一覧.extend(
        継ぎ口の宣言一覧
            .into_iter()
            .map(|(名前, 法線)| 側面の接合点(名前, 接合種別::ベイの継ぎ口, 法線)),
    );
    一覧.push(水平な面の接合点(骨格の上面の名前, 接合種別::上面積層, 2.6, 1.0, 2.0));
    一覧.push(水平な面の接合点(骨格の下面の名前, 接合種別::下面積層, 0.0, -1.0, 2.0));
    一覧.push(水平な面の接合点(床のはめ口の名前, 接合種別::床のはめ口, 0.16, 1.0, 1.68));
    一覧
}

/// 骨格の水平な面の接合点1件。**上方向が天頂でなく奥行なのは、面そのものが水平を向いているためである。**
/// 面は正方形であり、一辺は積層の口が2.00メートル、床のはめ口が1.68メートルである。
fn 水平な面の接合点(名前: &str, 種別: 接合種別, 高さ: f32, 法線のy成分: f32, 面の一辺: f32) -> 接合点 {
    接合点を作る(
        名前,
        種別,
        [0.0, 高さ, 0.0],
        [0.0, 法線のy成分, 0.0],
        [0.0, 0.0, 1.0],
        [面の一辺, 面の一辺],
    )
}

/// 骨格の側面の接合点1件。面の中心は法線の向きへ1.0メートル、床から1.3メートルの高さにあり、上方向は天頂である。
fn 側面の接合点(名前: &str, 種別: 接合種別, 法線: [f32; 3]) -> 接合点 {
    接合点を作る(名前, 種別, [法線[0], 1.3, 法線[2]], 法線, [0.0, 1.0, 0.0], [2.0, 2.6])
}

pub(super) fn 接合点を作る(
    名前: &str, 種別: 接合種別, 位置成分: [f32; 3], 向き: [f32; 3], 上方向: [f32; 3], 面: [f32; 2]
) -> 接合点 {
    let 姿勢 = 接合面の姿勢::生成する(方向を作る(向き), 方向を作る(上方向)).unwrap();
    接合点::生成する(
        接合点名::生成する(名前).unwrap(),
        種別,
        位置::<部品ローカル>::生成する(
            メートル::生成する(位置成分[0]),
            メートル::生成する(位置成分[1]),
            メートル::生成する(位置成分[2]),
        ),
        姿勢,
        接合面の形と寸法::矩形を生成する(メートル::生成する(面[0]), メートル::生成する(面[1])).unwrap(),
    )
}

fn 方向を作る(成分: [f32; 3]) -> 方向<部品ローカル> {
    方向::生成する(成分[0], 成分[1], 成分[2]).unwrap()
}
