//! 展開が正解表と同じ配置を出すことの試験。担当するのは、手順が据えた順に配置を積み上げることと、
//! 部品ごとにまとめた表が描画対象の単位になることを固定することである。
//! 材料は`expansion_fixture`が持つ。

#![allow(clippy::unwrap_used)]

use super::expander::展開器;
use super::expansion_fixture::{三階建てのカタログ, 原点の配置, 積み上げる手順};

/// 正解表の平行移動は 基礎[0,0,0]・2階[0,3.0,0]・3階[0,5.6,0.3] である。
#[test]
fn 積層の鎖は正解表と同じ配置を出す() {
    let 表 = 展開器::カタログを持たせて生成する(三階建てのカタログ())
        .手順を展開する(&積み上げる手順(), 原点の配置())
        .unwrap();
    let 期待 = [("基礎", [0.0, 0.0, 0.0]), ("2階", [0.0, 3.0, 0.0]), ("3階", [0.0, 5.6, 0.3])];
    assert_eq!(表.部品の種類数(), 3);
    assert_eq!(表.配置の総数(), 3);
    for (項目, (綴り, 期待の平行移動)) in 表.項目一覧().iter().zip(期待) {
        assert_eq!(項目.識別子().綴り(), 綴り);
        let 得た = 項目.配置一覧()[0].平行移動();
        assert!(
            得た.iter().zip(期待の平行移動).all(|(得, 期)| (得 - 期).abs() < 1.0e-5),
            "{綴り}の平行移動が正解表と違う: {得た:?}"
        );
    }
}
