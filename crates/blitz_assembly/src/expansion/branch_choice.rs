//! 幹の1節から枝を生やすかどうかの選択肢。担当するのは候補を保持することと、0以上1未満の値から1つを選ぶことである。
//!
//! 候補が空の指定を拒むのは、選べない選択肢が「選んだ結果が無い」という半端な状態を作るためである。
//! **「枝を生やさない」を表したいなら、それを候補の1つとして並べる。** 候補の数が選ばれる割合を決めるため、
//! 生やさない側を厚くしたいなら同じ枝を複数並べる。壁面の飾りと同じ様式である。
//!
//! 生え口を接合点の名前で指すのは、幹の一節が方位の違う生え口を複数持ち、どれを使うかが節ごとに変わるためである。
//! 実データの幹は黄金角137.5度ずつ回った3つの生え口を持つ。

use crate::joint::接合点名;

use super::choice_index::添字へ写す;
use super::error_rule::規則エラー;

/// 幹の1節から枝を生やすかどうかの1つの候補。
#[derive(Debug, Clone, PartialEq)]
pub enum 節の枝 {
    生やさない,
    生やす { 生え口: 接合点名 },
}

/// 幹の1節ごとに引く候補の並び。節の数だけこの並びから1件ずつ選ぶ。
#[derive(Debug, Clone, PartialEq)]
pub struct 節ごとの枝の候補 {
    候補一覧: Vec<節の枝>,
}

impl 節ごとの枝の候補 {
    pub fn 生成する(候補一覧: Vec<節の枝>) -> Result<Self, 規則エラー> {
        if 候補一覧.is_empty() {
            return Err(規則エラー::節の枝の候補が空である);
        }
        Ok(Self { 候補一覧 })
    }

    /// 0以上1未満の値から候補を1つ選ぶ。候補が空でないことを生成の時点で確かめてあるため、必ず1つ選べる。
    pub(super) fn 値から選ぶ(&self, 零以上一未満: f32) -> &節の枝 {
        let 添字 = 添字へ写す(零以上一未満, self.候補一覧.len());
        match self.候補一覧.get(添字) {
            Some(候補) => 候補,
            None => panic!("候補が空でないという不変条件に違反した"),
        }
    }
}
