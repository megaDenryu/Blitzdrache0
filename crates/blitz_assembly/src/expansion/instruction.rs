//! 組み立て手順: 根の部品から始めて、接合を1つずつ足していく指示の列。
//!
//! 親を部品IDでなく据えた番号で指すのは、同じ部品を何個でも置けるようにするためである。壁を4面に使う家では、
//! 部品IDが同じ部品が複数据わる。IDで指すと、どの1つを指しているのかが決まらない。
//!
//! **この手順はまだ乱数の種を持たない。** 段3で規則を導入し、壁の面ごとに窓壁か扉壁かを種から選ぶようになったとき、
//! 規則がこの手順を生む形になる。段2の手順は呼び出し側が直に書く宣言である。
//! 参照: `_doc/設計/部品カタログと接合点.md`「部品カタログと展開器」

use crate::joint::{接合点名, 接合面上の位置, 法線方向のずらし};

use super::super::part::部品ID;

/// 展開の途中で据わった部品を指す番号。根が0であり、指示を1つ実行するたびに1つ増える。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 据えた部品の番号(usize);

impl 据えた部品の番号 {
    pub fn 根() -> Self {
        Self(0)
    }

    pub fn 番号から生成する(番号: usize) -> Self {
        Self(番号)
    }

    pub(super) fn 添字(self) -> usize {
        self.0
    }

    /// 破れの文面へ載せる番号。読み手が手順のどの行を直すかを決めるために要る。
    pub fn 番号を返す(self) -> usize {
        self.0
    }
}

/// 既に据わっている部品の接合点へ、新しい部品を1つ繋ぐ指示。
#[derive(Debug, Clone)]
pub struct 接合の指示 {
    pub 親: 据えた部品の番号,
    pub 親の接合点: 接合点名,
    pub 子の部品: 部品ID,
    pub 子の接合点: 接合点名,
    /// 一致のときは中心以外を渡す余地が無い。包含のときだけ意味を持つ。
    pub 面上の位置: 接合面上の位置,
    /// 向かい合わせた位置から法線方向へ寄せる量。食い込ませて組む部品がここへ負の値を入れる。
    pub 法線方向のずらし: 法線方向のずらし,
}

/// 根の部品と、そこから枝を伸ばす指示の列。
#[derive(Debug, Clone)]
pub struct 組み立て手順 {
    根の部品: 部品ID,
    指示一覧: Vec<接合の指示>,
}

impl 組み立て手順 {
    pub fn 根と指示から生成する(根の部品: 部品ID, 指示一覧: Vec<接合の指示>) -> Self {
        Self { 根の部品, 指示一覧 }
    }

    pub fn 根の部品(&self) -> &部品ID {
        &self.根の部品
    }

    pub fn 指示一覧(&self) -> &[接合の指示] {
        &self.指示一覧
    }
}
