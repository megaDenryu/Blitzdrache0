//! 骨格を連ねた組み立ての姿勢の試験。担当するのは、上へ積んだ骨格の高さと、横へ継いだ骨格の進みと、
//! 継いだ面へ壁が入らないことを固定することである。
//!
//! **期待値は接合点の宣言から手で当てた値であり、実装の写しではない。** 骨格の上面は部品ローカルの高さ2.60、
//! 骨格の下面は0にあるため、向かい合わせると上の骨格の原点は2.60へ載る。右面の継ぎ口はX=+1.00、
//! 左面の継ぎ口はX=−1.00にあるため、向かい合わせると隣の骨格の原点はX=+2.00へ据わる。
//! **どちらの数も規則には1つも書かれていない。**
//!
//! 姿勢が恒等になる根拠も宣言から出る。向かい合う枠は法線と横軸を反転して縦軸をそのままにするため、
//! 上方向が同じ2つの口を向かい合わせると回転が消える。

#![allow(clippy::unwrap_used)]

use super::frame_chain_fixture::{平行移動が近いか, 恒等の姿勢か, 綴りごとの配置, 骨格の綴り};
use super::frame_chain_rule_fixture::{二段に積んだ骨格の規則, 横に二ベイ継いだ骨格の規則};
use super::frame_rule_fixture::規則と種で展開する;

/// 階高。骨格の上面の接合点の高さそのものである。
const 階高メートル: f32 = 2.6;

/// 隣のベイまでの横の進み。左右の継ぎ口の位置の差(1.00 −(−1.00))である。
const ベイの間隔メートル: f32 = 2.0;

/// 上の骨格が階高の高さへ恒等の姿勢で載る。**高さは規則でなく骨格の上面の宣言が決める。**
#[test]
fn 上へ積んだ骨格が階高の高さへ載る() {
    let 配置表 = 規則と種で展開する(&二段に積んだ骨格の規則(), 1);
    let 骨格一覧 = 綴りごとの配置(&配置表, 骨格の綴り);
    assert_eq!(骨格一覧.len(), 2, "骨格が2件据わっていない");
    assert!(平行移動が近いか(骨格一覧[0].平行移動(), [0.0, 0.0, 0.0]));
    let 上の骨格 = 骨格一覧[1];
    assert!(
        平行移動が近いか(上の骨格.平行移動(), [0.0, 階高メートル, 0.0]),
        "得た平行移動: {:?}",
        上の骨格.平行移動()
    );
    assert!(恒等の姿勢か(上の骨格.回転()), "得た回転: {:?}", 上の骨格.回転());
}

/// 上の階の壁が、下の階の壁と同じ水平位置の階高だけ上へ据わる。親の平行移動が子へ乗ることの確認である。
#[test]
fn 上の階の壁が下の階の真上へ据わる() {
    let 配置表 = 規則と種で展開する(&二段に積んだ骨格の規則(), 1);
    let 壁一覧: Vec<[f32; 3]> = 綴りごとの配置(&配置表, "平壁").iter().map(|配置| 配置.平行移動()).collect();
    assert_eq!(壁一覧.len(), 8, "両階で8枚の壁が据わっていない");
    for (下の階, 上の階) in 壁一覧[0..4].iter().zip(&壁一覧[4..8]) {
        let 期待 = [下の階[0], 下の階[1] + 階高メートル, 下の階[2]];
        assert!(平行移動が近いか(*上の階, 期待), "得た平行移動: {上の階:?} 期待: {期待:?}");
    }
}

/// 隣のベイが横へ間隔だけ進んだ位置へ恒等の姿勢で据わる。**進む量は規則でなく継ぎ口の宣言が決める。**
#[test]
fn 横へ継いだ骨格がベイの間隔だけ進む() {
    let 配置表 = 規則と種で展開する(&横に二ベイ継いだ骨格の規則(), 1);
    let 骨格一覧 = 綴りごとの配置(&配置表, 骨格の綴り);
    assert_eq!(骨格一覧.len(), 2, "骨格が2件据わっていない");
    let 隣のベイ = 骨格一覧[1];
    assert!(
        平行移動が近いか(隣のベイ.平行移動(), [ベイの間隔メートル, 0.0, 0.0]),
        "得た平行移動: {:?}",
        隣のベイ.平行移動()
    );
    assert!(恒等の姿勢か(隣のベイ.回転()), "得た回転: {:?}", 隣のベイ.回転());
}

/// 継いだ面へ壁が入らない。2つの骨格の8面のうち継ぎに使う2面を除く6面だけに壁が据わる。
/// **同じ物理面へ壁と隣のベイが二重に入る組み方が絵に出ないことを、この件数と位置が固定する。**
#[test]
fn 継いだ面には壁が入らない() {
    let 配置表 = 規則と種で展開する(&横に二ベイ継いだ骨格の規則(), 1);
    let 壁一覧: Vec<[f32; 3]> = 綴りごとの配置(&配置表, "平壁").iter().map(|配置| 配置.平行移動()).collect();
    let 期待一覧 = [
        [0.0, 0.0, 0.98],
        [0.0, 0.0, -0.98],
        [-0.98, 0.0, 0.0],
        [ベイの間隔メートル, 0.0, 0.98],
        [ベイの間隔メートル, 0.0, -0.98],
        [ベイの間隔メートル + 0.98, 0.0, 0.0],
    ];
    assert_eq!(壁一覧.len(), 期待一覧.len(), "継いだ面にも壁が入っている");
    for (得た, 期待) in 壁一覧.iter().zip(期待一覧) {
        assert!(平行移動が近いか(*得た, 期待), "得た平行移動: {得た:?} 期待: {期待:?}");
    }
}
