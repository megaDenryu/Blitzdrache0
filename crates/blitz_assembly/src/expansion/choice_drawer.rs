//! 候補を順に引く器: 1つの用途について、通し番号を進めながら0以上1未満の値を引く型。
//!
//! 種と用途と通し番号を1つの型が持つのは、引くたびに番号を進める規律をここへ閉じるためである。
//! 進め忘れると同じ値が続けて出て、並んだ候補がどれも同じ枝になる。
//!
//! **用途ごとに器を分けるのは、通し番号が用途をまたいで進むと、片方の引く回数がもう片方の引く値を動かすためである。**
//! 骨格の規則は壁の選択と継ぎ足しの選択の2つを引くが、継ぎ足しを1回引いたことで壁の選ばれ方が変わってはならない。

use super::generation_seed::{展開の用途, 生成の種};

pub(super) struct 候補を引く器 {
    種: 生成の種,
    用途: 展開の用途,
    通し番号: u64,
}

impl 候補を引く器 {
    pub(super) fn 種と用途から始める(種: 生成の種, 用途: 展開の用途) -> Self {
        Self {
            種, 用途, 通し番号: 0
        }
    }

    /// 次の0以上1未満の値を引き、通し番号を1つ進める。
    pub(super) fn 次の値を引く(&mut self) -> f32 {
        let 値 = self.種.混合の生成器を作る().零以上一未満(self.通し番号, self.用途.番号());
        self.通し番号 += 1;
        値
    }
}
