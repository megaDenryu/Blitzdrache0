//! 部品ごとの配置の集約: 何件ぶんもの展開の結果を、部品の種類ごとに1つの配置列へまとめる型。
//!
//! **この型が在ることが、描画発行数が件数に比例しない仕組みそのものである。** 100件ぶんの壁が1つの配置列へ入り、
//! 描画対象は部品の種類の数だけになる。件数が増えて伸びるのは配置列の長さだけである。
//!
//! 可変の列を型の中へ閉じるのは、取り込む途中の半端な集約を呼び出し側へ見せないためである。外から見えるのは、
//! 配置表を1件取り込むことと、まとまった眺めと員数を読むことだけである。
//!
//! 並びを最初に現れた順にするのは、描画対象の番号がこの順で決まり、同じ入力から同じ実行時形式のバイト列を得るためである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「設計の核心」

use super::super::part::部品ID;
use super::per_part_placements::部品ごとの配置;
use super::placement_table::部品ごとの配置表;

#[derive(Debug, Clone, PartialEq)]
pub struct 部品ごとの配置の集約 {
    項目一覧: Vec<部品ごとの配置>,
}

impl 部品ごとの配置の集約 {
    pub fn 空から始める() -> Self {
        Self { 項目一覧: Vec::new() }
    }

    /// 個体1件を展開した配置表を取り込む。同じ部品が既にあればその配置列へ足し、無ければ末尾へ新しい項目を作る。
    pub fn 配置表を1件取り込む(&mut self, 配置表: &部品ごとの配置表) {
        for 据えた in 配置表.据えた順() {
            self.項目を引くか作る(据えた.識別子()).配置を1件足す(据えた.配置());
        }
    }

    /// 部品の種類ごとにまとめた眺め。**これが描画対象の単位になる。**
    pub fn 項目一覧(&self) -> &[部品ごとの配置] {
        &self.項目一覧
    }

    /// 描画対象の数になる値。部品の種類数であり、据えた個体の数ではない。
    pub fn 部品の種類数(&self) -> usize {
        self.項目一覧.len()
    }

    /// 取り込んだ全部の配置の件数。件数に比例して増える唯一の数である。
    pub fn 配置の総数(&self) -> usize {
        self.項目一覧.iter().map(|項目| 項目.配置一覧().len()).sum()
    }

    fn 項目を引くか作る(&mut self, 識別子: &部品ID) -> &mut 部品ごとの配置 {
        let 位置 = match self.項目一覧.iter().position(|項目| 項目.識別子() == 識別子) {
            Some(位置) => 位置,
            None => {
                self.項目一覧.push(部品ごとの配置::識別子から空で始める(識別子.clone()));
                self.項目一覧.len() - 1
            }
        };
        match self.項目一覧.get_mut(位置) {
            Some(項目) => 項目,
            None => panic!("引くか作るかで決めた位置が並びの外にあるという不変条件に違反した"),
        }
    }
}
