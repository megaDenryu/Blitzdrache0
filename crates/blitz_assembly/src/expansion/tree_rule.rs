//! 木の規則: 幹を上へ継いで細くし、節ごとに枝を1本まで生やし、その先へ葉房を付け、幹の頂を冠の葉房で塞ぐ規則。
//!
//! **倍率をどこにも書かない。** 幹が上へ行くほど細くなるのは、幹頂部の直径を幹基部の直径で割った比を接合が導くからである。
//! 規則が持つのは「何節積むか」と「節ごとに何を候補から選ぶか」だけであり、太さは部品の宣言が決める。
//!
//! **枝を生やす節を規則が指さない。** 節ごとに候補を1件引く形にしたため、幹より高い位置の節を指す誤りが構造的に起きない。
//! 枝の本数は候補の引き方で決まり、節の数を超えない。
//!
//! **冠は必ず載せる。** 幹頂部が噛み合う相手は幹基部だけであり、葉房が幹基部の口を持つことでこの接合が成り立つ。
//! 載せない選択を候補で表さないのは、幹の切り口が絵に出る形を規則が選べるようにする理由が今は無いためである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「一致の様式は子の倍率を導出する」

use super::branch_choice::節ごとの枝の候補;
use super::generation_seed::生成の種;
use super::instruction::{据えた部品の番号, 組み立て手順};
use super::tree_parts::{幹の指定, 枝の指定, 葉房の指定};
use super::tree_step_builder::木の手順の組み手;
use super::trunk_segment::幹の節数;

#[derive(Debug, Clone, PartialEq)]
pub struct 木の規則 {
    幹: 幹の指定,
    幹の節数: 幹の節数,
    節ごとの枝の候補: 節ごとの枝の候補,
    枝: 枝の指定,
    葉房: 葉房の指定,
}

impl 木の規則 {
    /// 破れうる前提を持たないため失敗しない。節数が零でないことは`幹の節数`が、候補が空でないことは
    /// `節ごとの枝の候補`が、それぞれ生成の時点で拒んでいる。
    pub fn 生成する(
        幹: 幹の指定, 幹の節数: 幹の節数, 節ごとの枝の候補: 節ごとの枝の候補, 枝: 枝の指定, 葉房: 葉房の指定
    ) -> Self {
        Self {
            幹,
            幹の節数,
            節ごとの枝の候補,
            枝,
            葉房,
        }
    }

    /// 根の幹から順に、幹を継ぎ、節ごとに枝と葉房を足し、最後に冠を載せる手順を組む。
    /// 幹を先に全部積んでから枝を足すのは、枝が親の節の番号を要り、番号は据えた順で決まるためである。
    pub(super) fn 種から手順を生む(&self, 種: 生成の種) -> 組み立て手順 {
        let mut 組み手 = 木の手順の組み手::根の幹から始める(種);
        let mut 節の番号一覧 = vec![据えた部品の番号::根()];
        for _ in 1..self.幹の節数.値() {
            let 直前の節 = 節の番号一覧[節の番号一覧.len() - 1];
            節の番号一覧.push(組み手.幹を1節継ぐ(&self.幹, 直前の節));
        }
        for 節の番号 in &節の番号一覧 {
            組み手.節へ枝と葉房を足す(&self.節ごとの枝の候補, *節の番号, &self.枝, &self.葉房);
        }
        let 最上節 = 節の番号一覧[節の番号一覧.len() - 1];
        組み手.冠を載せる(&self.幹, 最上節, &self.葉房);
        組み立て手順::根と指示から生成する(self.幹.部品.clone(), 組み手.指示一覧へ畳む())
    }
}
