//! 木の規則: 幹を上へ継いで細くし、指定した節から枝を1本生やし、その先へ葉房を付ける規則。
//!
//! **倍率をどこにも書かない。** 幹が上へ行くほど細くなるのは、幹頂部の直径を幹基部の直径で割った比を接合が導くからである。
//! 規則が持つのは「何節積むか」と「どの節から枝を出すか」だけであり、太さは部品の宣言が決める。
//!
//! **種を受け取らない。** 幹の節数も枝の位置も規則が決めており、選ぶ余地がまだ無い。個体ごとに姿を変えるのは、
//! 枝の本数と向きを候補から選ぶようにするときであり、そのとき初めて種がここへ効く。
//! 参照: `_doc/設計/部品カタログと接合点.md`「一致の様式は子の倍率を導出する」

use crate::joint::{接合面上の位置, 法線方向のずらし};

use super::error_rule::規則エラー;
use super::instruction::{据えた部品の番号, 接合の指示, 組み立て手順};
use super::instruction_list_builder::指示の並びの組み手;
use super::tree_parts::{幹の指定, 枝の指定, 葉房の指定};
use super::trunk_segment::{幹の節の番号, 幹の節数};

#[derive(Debug, Clone, PartialEq)]
pub struct 木の規則 {
    幹: 幹の指定,
    幹の節数: 幹の節数,
    枝を生やす節: 幹の節の番号,
    枝: 枝の指定,
    葉房: 葉房の指定,
}

impl 木の規則 {
    /// 幹より高い位置から枝を生やす規則を拒む。据わっていない節を親に指す手順は、展開の途中で初めて落ちる。
    pub fn 生成する(
        幹: 幹の指定,
        幹の節数: 幹の節数,
        枝を生やす節: 幹の節の番号,
        枝: 枝の指定,
        葉房: 葉房の指定,
    ) -> Result<Self, 規則エラー> {
        if !枝を生やす節.節数の内側か(幹の節数) {
            return Err(規則エラー::枝を生やす節が幹の節数を超える {
                節の番号: 枝を生やす節.値(),
                幹の節数: 幹の節数.値(),
            });
        }
        Ok(Self {
            幹,
            幹の節数,
            枝を生やす節,
            枝,
            葉房,
        })
    }

    /// 根の幹から順に、幹を継ぎ、枝を生やし、葉房を付ける手順を組む。
    pub(super) fn 手順を生む(&self) -> 組み立て手順 {
        let mut 組み手 = 指示の並びの組み手::空から始める();
        let mut 節の番号一覧 = vec![据えた部品の番号::根()];
        for _ in 1..self.幹の節数.値() {
            let 直前の節 = 節の番号一覧[節の番号一覧.len() - 1];
            節の番号一覧.push(組み手.接合を1つ積む(self.幹を1節継ぐ指示(直前の節)));
        }
        let 枝の親 = 節の番号一覧[self.枝を生やす節.値() - 1];
        let 枝の番号 = 組み手.接合を1つ積む(self.枝を生やす指示(枝の親));
        組み手.接合を1つ積む(self.葉房を付ける指示(枝の番号));
        組み立て手順::根と指示から生成する(self.幹.部品.clone(), 組み手.指示一覧へ畳む())
    }

    fn 幹を1節継ぐ指示(&self, 直前の節: 据えた部品の番号) -> 接合の指示 {
        接合の指示 {
            親: 直前の節,
            親の接合点: self.幹.頂部.clone(),
            子の部品: self.幹.部品.clone(),
            子の接合点: self.幹.基部.clone(),
            面上の位置: 接合面上の位置::中心(),
            法線方向のずらし: 法線方向のずらし::寄せない(),
        }
    }

    fn 枝を生やす指示(&self, 幹の節: 据えた部品の番号) -> 接合の指示 {
        接合の指示 {
            親: 幹の節,
            親の接合点: self.幹.枝の生え口.clone(),
            子の部品: self.枝.部品.clone(),
            子の接合点: self.枝.根元.clone(),
            面上の位置: 接合面上の位置::中心(),
            法線方向のずらし: 法線方向のずらし::寄せない(),
        }
    }

    fn 葉房を付ける指示(&self, 枝: 据えた部品の番号) -> 接合の指示 {
        接合の指示 {
            親: 枝,
            親の接合点: self.枝.頂芽.clone(),
            子の部品: self.葉房.部品.clone(),
            子の接合点: self.葉房.根元.clone(),
            面上の位置: 接合面上の位置::中心(),
            法線方向のずらし: 法線方向のずらし::寄せない(),
        }
    }
}
