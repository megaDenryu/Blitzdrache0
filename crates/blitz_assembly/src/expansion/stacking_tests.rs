//! 階を積む道の試験。担当するのは、壁の飾りを先に足しても次の階が飾りでなく直前の階の上へ乗ることを固定することである。
//!
//! 選択の試験と分けているのは、こちらが積む道を見るのに対し、あちらが選ぶ道を見るためである。
//! この試験が無いと、積む階の一覧が空の規則ばかりを試して積む道が一度も動かないまま通る。実際にそうなっていた。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::expander::展開器;
use super::expansion_fixture::{原点の配置, 名前, 識別子};
use super::generation_seed::生成の種;
use super::house_rule::{家の規則, 積む階};
use super::rule::組み立て規則;
use super::wall_choice::{壁面の指定, 壁面の飾り};
use super::wall_fixture::二階建てで壁面を持つカタログ;
use crate::joint::法線方向のずらし;

/// 壁の飾りを先に足しても、次の階は飾りでなく直前の階の上へ乗る。
/// 「直前に据えた部品」を親にすると、土台の壁へ付けた出窓の上へ2階が乗る。
#[test]
fn 階は飾りでなく直前の階の上へ乗る() {
    let 必ず付ける = |接合点: &str| {
        壁面の指定::生成する(
            名前(接合点),
            vec![壁面の飾り::付ける {
                部品: 識別子("出窓"),
                接合点: 名前("差込口"),
                横のずらし: メートル::生成する(0.0),
                法線方向のずらし: 法線方向のずらし::寄せない(),
            }],
        )
        .unwrap()
    };
    let 規則 = 組み立て規則::家(家の規則::生成する(
        識別子("土台"),
        vec![必ず付ける("正面壁")],
        vec![積む階 {
            部品: 識別子("2階"),
            親の上面: 名前("上面"),
            自分の下面: 名前("下面"),
            壁面一覧: vec![必ず付ける("2階の正面壁")],
        }],
    ));
    let 表 = 展開器::カタログを持たせて生成する(二階建てで壁面を持つカタログ())
        .規則から展開する(&規則, 生成の種::値から生成する(7), 原点の配置())
        .unwrap();
    let 二階の配置 = 表.据えた順()[2].配置().平行移動();
    assert!(
        (二階の配置[1] - 3.0).abs() < 1.0e-5,
        "2階が土台の上面(高さ3.0)でなく別の部品の上へ乗った: {二階の配置:?}"
    );
}
