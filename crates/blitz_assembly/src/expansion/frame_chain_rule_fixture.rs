//! 骨格を連ねた5つの規則の試験の材料。上へ2段積む・横へ2ベイ継ぐ・屋根を載せた1ベイの家・屋根を載せた2段の家・
//! 上面へ三択を置いた規則である。読み出しの口とはめ口一覧の組み方は`frame_chain_fixture`が持つ。
//!
//! 1ベイ1段の規則(`frame_rule_fixture`)と分けるのは、確かめる軸が違うためである。あちらは壁の候補の選ばれ方を見る。
//! こちらは骨格どうしの接合が導く高さと横の進み、および継ぎ足しの候補の選ばれ方を見る。
//!
//! 三択の規則を除いて候補を1つに固定してあるのは、接合が導く数を種の影響なしに見るためである。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::frame_bay_joint_fixture::{骨格の上面の名前, 骨格の下面の名前};
use super::frame_chain_fixture::{四面すべてのはめ口の綴り, 平壁を必ず入れるはめ口一覧};
use super::frame_extension::{継ぎ足しの指定, 骨格へ継ぎ足すもの};
use super::frame_fixture::{名前, 屋根の部品, 骨格の部品};
use super::frame_rule::一間四方の骨格の規則;
use super::rule::組み立て規則;

fn 骨格を継ぐ候補(自分の接合点: &str, 面の綴り一覧: &[&str]) -> 骨格へ継ぎ足すもの {
    骨格へ継ぎ足すもの::骨格を継ぐ {
        自分の接合点: 名前(自分の接合点),
        はめ口一覧: 平壁を必ず入れるはめ口一覧(面の綴り一覧),
    }
}

fn 屋根を載せる候補() -> 骨格へ継ぎ足すもの {
    骨格へ継ぎ足すもの::屋根を載せる {
        部品: 屋根の部品(),
        下面: 名前("屋根の下面"),
    }
}

fn 上面の継ぎ足し(候補一覧: Vec<骨格へ継ぎ足すもの>) -> 継ぎ足しの指定 {
    継ぎ足しの指定::生成する(名前(骨格の上面の名前), 候補一覧).unwrap()
}

fn 四面へ平壁を入れた規則(連なり: Vec<継ぎ足しの指定>) -> 組み立て規則 {
    組み立て規則::一間四方の骨格(一間四方の骨格の規則::生成する(
        骨格の部品(),
        平壁を必ず入れるはめ口一覧(&四面すべてのはめ口の綴り()),
        連なり,
    ))
}

/// 上へ2段積み、両階の4面すべてへ平壁を入れる規則。階の高さが骨格の上面の宣言から導かれることを見る。
pub(super) fn 二段に積んだ骨格の規則() -> 組み立て規則 {
    四面へ平壁を入れた規則(vec![上面の継ぎ足し(vec![骨格を継ぐ候補(
        骨格の下面の名前,
        &四面すべてのはめ口の綴り(),
    )])])
}

/// 横へ2ベイ継ぎ、継いだ面を除く6面へ平壁を入れる規則。横へ進む量が継ぎ口の宣言から導かれることを見る。
pub(super) fn 横に二ベイ継いだ骨格の規則() -> 組み立て規則 {
    let 右のベイ = 継ぎ足しの指定::生成する(
        名前("右面の継ぎ口"),
        vec![骨格を継ぐ候補("左面の継ぎ口", &["正面のはめ口", "背面のはめ口", "右面のはめ口"])],
    )
    .unwrap();
    組み立て規則::一間四方の骨格(一間四方の骨格の規則::生成する(
        骨格の部品(),
        平壁を必ず入れるはめ口一覧(&["正面のはめ口", "背面のはめ口", "左面のはめ口"]),
        vec![右のベイ],
    ))
}

/// 1ベイの上へ屋根を載せる規則。屋根が載る高さが骨格の上面の宣言から導かれることを見る。
pub(super) fn 屋根を載せた一間四方の家の規則() -> 組み立て規則 {
    四面へ平壁を入れた規則(vec![上面の継ぎ足し(vec![屋根を載せる候補()])])
}

/// 2段積みの上へ屋根を載せる規則。屋根の高さが階高の2段ぶんの累和になることを見る。
pub(super) fn 屋根を載せた二段の家の規則() -> 組み立て規則 {
    四面へ平壁を入れた規則(vec![
        上面の継ぎ足し(vec![骨格を継ぐ候補(骨格の下面の名前, &四面すべてのはめ口の綴り())]),
        上面の継ぎ足し(vec![屋根を載せる候補()]),
    ])
}

/// 上面へ三択(骨格を積む・屋根を載せる・何も継がない)を置き、その先へもう1段の屋根を置いた規則。
/// 候補のどの枝も選ばれうることと、骨格以外を継いだ時点で連なりが閉じることを見る。
pub(super) fn 上面が三択の規則() -> 組み立て規則 {
    四面へ平壁を入れた規則(vec![
        上面の継ぎ足し(vec![
            骨格を継ぐ候補(骨格の下面の名前, &四面すべてのはめ口の綴り()),
            屋根を載せる候補(),
            骨格へ継ぎ足すもの::継ぎ足さない,
        ]),
        上面の継ぎ足し(vec![屋根を載せる候補()]),
    ])
}
