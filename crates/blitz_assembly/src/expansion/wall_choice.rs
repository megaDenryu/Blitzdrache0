//! 壁面1つに何を付けるかの選択肢。担当するのは候補を保持することと、0以上1未満の値から1つを選ぶことである。
//!
//! 候補が空の指定を拒むのは、選べない選択肢が「選んだ結果が無い」という半端な状態を作るためである。
//! **「何も付けない」を表したいなら、それを候補の1つとして並べる。** 候補の数が選ばれる割合を決めるため、
//! 付けない側を厚くしたいなら同じ枝を複数並べる。割合を別の数で持つと、候補の並びと割合の2つを揃える手間が生まれる。

use blitz_math::メートル;

use super::super::part::部品ID;
use super::error_rule::規則エラー;
use crate::joint::接合点名;

/// 壁面へ付けるものの1つの候補。
#[derive(Debug, Clone, PartialEq)]
pub enum 壁面の飾り {
    付けない,
    付ける {
        部品: 部品ID,
        接合点: 接合点名,
        /// 面の中心から横へずらす量。部品の寸法から導けない意匠の決定である。
        横のずらし: メートル,
    },
}

/// 1つの壁面と、そこへ付ける候補の並び。
#[derive(Debug, Clone, PartialEq)]
pub struct 壁面の指定 {
    接合点: 接合点名,
    候補一覧: Vec<壁面の飾り>,
}

impl 壁面の指定 {
    pub fn 生成する(接合点: 接合点名, 候補一覧: Vec<壁面の飾り>) -> Result<Self, 規則エラー> {
        if 候補一覧.is_empty() {
            return Err(規則エラー::壁面の候補が空である {
                接合点の名前: 接合点
            });
        }
        Ok(Self { 接合点, 候補一覧 })
    }

    pub fn 接合点(&self) -> &接合点名 {
        &self.接合点
    }

    /// 0以上1未満の値から候補を1つ選ぶ。候補が空でないことを生成の時点で確かめてあるため、必ず1つ選べる。
    pub(super) fn 値から選ぶ(&self, 零以上一未満: f32) -> &壁面の飾り {
        let 添字 = 添字へ写す(零以上一未満, self.候補一覧.len());
        match self.候補一覧.get(添字) {
            Some(候補) => 候補,
            None => panic!("候補が空でないという不変条件に違反した"),
        }
    }
}

/// 0以上1未満の値を候補の添字へ写す。候補の件数で等分し、値が入る区間の番号を返す。
///
/// 小数から整数への変換を持たないのは、標準ライブラリが型付きの変換を持たず、`as`による縮小変換を規約が禁じているためである。
/// 代わりに区間の上の境界と比べて進む。候補は高々数件であり、走査の費用は問題にならない。
fn 添字へ写す(零以上一未満: f32, 件数: usize) -> usize {
    let 件数の小数 = 小数へ写す(件数);
    let mut 添字 = 0;
    while 添字 + 1 < 件数 {
        let 上の境界 = 小数へ写す(添字 + 1) / 件数の小数;
        if 零以上一未満 < 上の境界 {
            break;
        }
        添字 += 1;
    }
    添字
}

fn 小数へ写す(値: usize) -> f32 {
    u16::try_from(値).map_or(f32::from(u16::MAX), f32::from)
}
