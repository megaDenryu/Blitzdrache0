//! 骨格を連ねた2つの規則の試験の材料。上へ2段積む規則と、横へ2ベイ継ぐ規則と、組み上がった配置を読み出す口である。
//!
//! 1ベイ1段の規則(`frame_rule_fixture`)と分けるのは、確かめる軸が違うためである。あちらは候補の選ばれ方を見る。
//! こちらは骨格どうしの接合が導く高さと横の進みを見るため、候補を1つに固定して種の影響を消してある。
//!
//! 継いだ面のはめ口を並べないことが、壁と隣のベイが同じ面へ二重に入るのを防ぐ。**この排他は規則の責務であり、
//! 接合の契約は課さない。** 材料の側でも同じ規律で書き、規則の宣言がそのまま絵の形になることを見せる。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_engine::個体配置;

use super::frame_bay_joint_fixture::{はめ口の宣言一覧, 骨格の上面の名前, 骨格の下面の名前};
use super::frame_extension::骨格の継ぎ足し;
use super::frame_fixture::{名前, 識別子, 骨格の部品};
use super::frame_rule::一間四方の骨格の規則;
use super::frame_rule_fixture::壁をはめる候補;
use super::opening_choice::はめ口の指定;
use super::placement_table::部品ごとの配置表;
use super::rule::組み立て規則;

/// 骨格の部品の綴り。試験が骨格と壁を数え分けるために使う。
pub(super) const 骨格の綴り: &str = "一間四方の骨格";

/// 配置表から、名指した部品の配置を据えた順に取り出す。
pub(super) fn 綴りごとの配置(配置表: &部品ごとの配置表, 綴り: &str) -> Vec<個体配置> {
    配置表
        .据えた順()
        .iter()
        .filter(|据えた| 据えた.識別子() == &識別子(綴り))
        .map(|据えた| 据えた.配置())
        .collect()
}

pub(super) fn 平行移動が近いか(得た: [f32; 3], 期待: [f32; 3]) -> bool {
    得た.iter().zip(期待).all(|(得, 期)| (得 - 期).abs() < 1.0e-5)
}

pub(super) fn 恒等の姿勢か(回転: [f32; 4]) -> bool {
    回転[0].abs() < 1.0e-5 && 回転[1].abs() < 1.0e-5 && 回転[2].abs() < 1.0e-5 && (回転[3].abs() - 1.0).abs() < 1.0e-5
}

/// 名指した面へ平壁を必ず1枚入れるはめ口の指定を並べる。候補を1つにして、どの種でも同じ壁が同じ面へ入るようにする。
fn 平壁を必ず入れるはめ口一覧(面の綴り一覧: &[&str]) -> Vec<はめ口の指定> {
    面の綴り一覧
        .iter()
        .map(|綴り| はめ口の指定::生成する(名前(綴り), vec![壁をはめる候補("平壁")]).unwrap())
        .collect()
}

fn 四面すべてのはめ口の綴り() -> Vec<&'static str> {
    はめ口の宣言一覧.into_iter().map(|(綴り, _)| 綴り).collect()
}

/// 骨格を上へ2段積み、両階の4面すべてへ平壁を入れる規則。階の高さが骨格の上面の宣言から導かれることを見る。
pub(super) fn 二段に積んだ骨格の規則() -> 組み立て規則 {
    let 二階 = 骨格の継ぎ足し::生成する(
        名前(骨格の上面の名前),
        名前(骨格の下面の名前),
        平壁を必ず入れるはめ口一覧(&四面すべてのはめ口の綴り()),
    );
    組み立て規則::一間四方の骨格(一間四方の骨格の規則::生成する(
        骨格の部品(),
        平壁を必ず入れるはめ口一覧(&四面すべてのはめ口の綴り()),
        vec![二階],
    ))
}

/// 骨格を横へ2ベイ継ぎ、継いだ面を除く6面へ平壁を入れる規則。横へ進む量が継ぎ口の宣言から導かれることを見る。
pub(super) fn 横に二ベイ継いだ骨格の規則() -> 組み立て規則 {
    let 右のベイ = 骨格の継ぎ足し::生成する(
        名前("右面の継ぎ口"),
        名前("左面の継ぎ口"),
        平壁を必ず入れるはめ口一覧(&["正面のはめ口", "背面のはめ口", "右面のはめ口"]),
    );
    組み立て規則::一間四方の骨格(一間四方の骨格の規則::生成する(
        骨格の部品(),
        平壁を必ず入れるはめ口一覧(&["正面のはめ口", "背面のはめ口", "左面のはめ口"]),
        vec![右のベイ],
    ))
}
