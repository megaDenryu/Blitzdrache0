//! 骨格のはめ口1つへ何を入れるかの選択肢。担当するのは候補を保持することと、0以上1未満の値から1つを選ぶことである。
//!
//! 候補が空の指定を拒むのは、選べない選択肢が「選んだ結果が無い」という半端な状態を作るためである。
//! **「何も入れない」を表したいなら、それを候補の1つとして並べる。** 候補の数が選ばれる割合を決めるため、
//! 入れない側を厚くしたいなら同じ枝を複数並べる。壁面の飾りと節の枝と同じ様式である。
//!
//! **壁面の飾りを流用しないのは、あちらが横のずらしを持つためである。** はめ口と外枠の対は一致の様式であり、
//! 面に沿って滑らせる自由度を持たない。流用すると宣言が横のずらしを書ける形になる。型で書けない形にするのが
//! 第一の防壁であり、一致の様式が中心以外を拒む判定は第二の防壁である。あわせて名前が実体と合わない。
//! 壁面の飾りは壁の面へ飾りを差し込むことであり、はめ口へ壁そのものをはめることではない。
//! **`壁をはめる`だけが外面の飾りの選択を持つ。** 壁の無い面へ飾りだけが浮く宣言を型で書けなくするためである。
//! `法線方向のずらし`を零にすると骨格の柱と梁の外面と壁の背面がちょうど同一平面になり、深度が競合する。
//! この破れは接触の検査に掛からず絵にだけ出る。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格と壁の対、扉の対」

use super::super::part::部品ID;
use super::choice_index::添字へ写す;
use super::error_rule::規則エラー;
use super::frame_ornament::壁の外面の飾りの指定;
use super::instruction::{据えた部品の番号, 接合の指示};
use crate::joint::{接合点名, 接合面上の位置, 法線方向のずらし};

/// はめ口1つへ入れるものの1つの候補。
#[derive(Debug, Clone, PartialEq)]
pub enum はめ口へ入れるもの {
    入れない,
    壁をはめる {
        部品: 部品ID,
        外枠: 接合点名, // 壁の側の接合点。骨格のはめ口と一致の様式で噛み合う
        外面の飾り: 壁の外面の飾りの指定, // この壁の外面へ何を差し込むかの選択
        法線方向のずらし: 法線方向のずらし, // 骨格の面へ壁を食い込ませる量
    },
}

impl はめ口へ入れるもの {
    /// この候補が入れる壁の外面の飾りの選択。入れない候補は飾りを持たない。
    pub(super) fn 外面の飾りの指定(&self) -> Option<&壁の外面の飾りの指定> {
        match self {
            Self::入れない => None,
            Self::壁をはめる { 外面の飾り, .. } => Some(外面の飾り),
        }
    }

    /// 名指した骨格の名指したはめ口へこの候補を入れる指示。入れない候補では指示が1件も出ない。
    /// **一致の様式であるため、面上の位置は中心のほかに置きようがない。**
    pub(super) fn 指示にする(&self, 親: 据えた部品の番号, はめ口: &接合点名) -> Option<接合の指示> {
        let Self::壁をはめる {
            部品,
            外枠,
            法線方向のずらし,
            ..
        } = self
        else {
            return None;
        };
        Some(接合の指示 {
            親,
            親の接合点: はめ口.clone(),
            子の部品: 部品.clone(),
            子の接合点: 外枠.clone(),
            面上の位置: 接合面上の位置::中心(),
            法線方向のずらし: *法線方向のずらし,
        })
    }
}

/// 骨格のはめ口1つと、そこへ入れる候補の並び。
#[derive(Debug, Clone, PartialEq)]
pub struct はめ口の指定 {
    はめ口: 接合点名,
    候補一覧: Vec<はめ口へ入れるもの>,
}

impl はめ口の指定 {
    pub fn 生成する(はめ口: 接合点名, 候補一覧: Vec<はめ口へ入れるもの>) -> Result<Self, 規則エラー> {
        if 候補一覧.is_empty() {
            return Err(規則エラー::はめ口の候補が空である {
                はめ口の名前: はめ口
            });
        }
        Ok(Self { はめ口, 候補一覧 })
    }

    pub fn はめ口(&self) -> &接合点名 {
        &self.はめ口
    }

    /// 0以上1未満の値から候補を1つ選ぶ。候補が空でないことを生成の時点で確かめてあるため、必ず1つ選べる。
    pub(super) fn 値から選ぶ(&self, 零以上一未満: f32) -> &はめ口へ入れるもの {
        let 添字 = 添字へ写す(零以上一未満, self.候補一覧.len());
        match self.候補一覧.get(添字) {
            Some(候補) => 候補,
            None => panic!("候補が空でないという不変条件に違反した"),
        }
    }
}
