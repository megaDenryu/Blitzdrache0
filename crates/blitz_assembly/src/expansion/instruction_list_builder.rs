//! 指示の並びの組み手: 組み立て手順の指示を順に積み、据えた部品の番号を数える型。
//!
//! 番号を数える規律をここが1箇所で持つ。**指示を1つ足すと据えた部品が1つ増え、その部品の番号は根から数えた件数である。**
//! この規律を規則ごとに書き直すと、番号のずれが「親がまだ据わっていない」という遠い場所の失敗として現れる。
//! 家の規則も木の規則もこの型を通して指示を積む。
//!
//! 展開の層の外へ見せているのは、ベイ格子の変換も同じ規律で指示を積むためである。番号を数える規律の写しを
//! 層ごとに持つと、同じずれが層の数だけ生まれる。見せる範囲はこのクレートの中に閉じる。

use super::instruction::{据えた部品の番号, 接合の指示};

pub(crate) struct 指示の並びの組み手 {
    指示一覧: Vec<接合の指示>,
}

impl 指示の並びの組み手 {
    pub(crate) fn 空から始める() -> Self {
        Self { 指示一覧: Vec::new() }
    }

    /// 指示を1つ積み、そこで据わる部品の番号を返す。根が0であるため、番号は積んだ後の件数と等しい。
    pub(crate) fn 接合を1つ積む(&mut self, 指示: 接合の指示) -> 据えた部品の番号 {
        self.指示一覧.push(指示);
        据えた部品の番号::番号から生成する(self.指示一覧.len())
    }

    /// 組み立てた指示の列を取り出して閉じる。以降この組み手は使えない。
    pub(crate) fn 指示一覧へ畳む(self) -> Vec<接合の指示> {
        self.指示一覧
    }
}
