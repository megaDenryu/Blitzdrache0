//! 幹の節の数え方。担当するのは、木が何節積まれるかを裸の整数と取り違えない形で持つことである。
//!
//! **1から数える。** 根に据わる幹の一節が1節目であり、0節の木は木でないため型で拒む。
//! 枝をどの節から出すかを指す番号を持たないのは、規則が節ごとに候補を1件引く形になり、
//! 節を名指しする必要が無くなったためである(幹より高い節を指す誤りが構造的に起きない)。

use super::error_rule::規則エラー;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct 幹の節数(usize);

impl 幹の節数 {
    /// 零を拒む。根の1節は必ず据わるため、節数の下限は1である。
    pub fn 生成する(節数: usize) -> Result<Self, 規則エラー> {
        if 節数 == 0 {
            return Err(規則エラー::幹の節数が零である);
        }
        Ok(Self(節数))
    }

    pub fn 値(self) -> usize {
        self.0
    }
}
