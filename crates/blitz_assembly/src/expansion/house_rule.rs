//! 家の規則: 土台の上へ階を積み、各階の壁面へ候補から選んだ飾りを付ける規則。
//!
//! **規則が手順を生む。** 手順を直に書くのは段2までの形であり、ここからは規則と種が手順を決める。
//! 展開器は生まれた手順をそのまま展開するため、規則が増えても展開の側は変わらない。
//!
//! 選択の添字を規則ぜんたいで通しにするのは、階ごとに数え直すと、階の数が違う家の同じ位置の壁が
//! 同じ値を引いてしまうためである。通しにすると壁面が1つ増えるだけで以降の選択がすべて変わる。

use super::super::part::部品ID;
use super::generation_seed::生成の種;
use super::instruction::{据えた部品の番号, 組み立て手順};
use super::step_builder::手順の組み手;
use super::wall_choice::壁面の指定;
use crate::joint::接合点名;

/// 土台の上へ積む階1つ。親の上面と自分の下面で繋ぎ、自分の壁面へ飾りを付ける。
#[derive(Debug, Clone, PartialEq)]
pub struct 積む階 {
    pub 部品: 部品ID,
    pub 親の上面: 接合点名,
    pub 自分の下面: 接合点名,
    pub 壁面一覧: Vec<壁面の指定>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct 家の規則 {
    土台: 部品ID,
    土台の壁面一覧: Vec<壁面の指定>,
    積む階一覧: Vec<積む階>,
}

impl 家の規則 {
    pub fn 生成する(土台: 部品ID, 土台の壁面一覧: Vec<壁面の指定>, 積む階一覧: Vec<積む階>) -> Self {
        Self {
            土台,
            土台の壁面一覧,
            積む階一覧,
        }
    }

    /// 種から手順を生む。同じ種と同じ規則からは常に同じ手順が出る。
    pub(super) fn 種から手順を生む(&self, 種: 生成の種) -> 組み立て手順 {
        let mut 組み手 = 手順の組み手::土台から始める(種);
        組み手.壁面の飾りを足す(&self.土台の壁面一覧, 据えた部品の番号::根());
        for 階 in &self.積む階一覧 {
            let 階の番号 = 組み手.階を積む(階);
            組み手.壁面の飾りを足す(&階.壁面一覧, 階の番号);
        }
        組み立て手順::根と指示から生成する(self.土台.clone(), 組み手.指示一覧へ畳む())
    }
}
