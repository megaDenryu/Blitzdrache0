//! 骨格へはめた壁の姿勢の試験。担当するのは、4つのはめ口が壁を天頂軸まわりの4分の1回転ずつ違う向きへ立てることと、
//! 壁が骨格の面より外側へ出ることを固定することである。
//!
//! **期待値は接合面の姿勢の定義から手で当てた値であり、実装の写しではない。** 向かい合う枠は法線と横軸を反転して
//! 縦軸をそのままにするため、上方向が天頂で揃った4つのはめ口では、壁の回転が天頂軸まわりだけになる。
//! 正面(法線+Z)が180度、背面(法線-Z)が恒等、左面(法線-X)が+90度、右面(法線+X)が-90度である。
//!
//! 壁の本体は自分の外枠の面より奥(部品ローカルのzが-0.2から0)にある。向かい合わせるとこの奥行が骨格の面の外側へ
//! 写るため、**組んだベイの外寸は骨格の2.00四方でなく2.40四方になる。** 平行移動が0.98であることは、
//! 食い込ませる量0.02だけ壁の背面が骨格の柱の外面(1.00)より内側にあることを意味する。

#![allow(clippy::unwrap_used)]

use super::frame_fixture::識別子;
use super::frame_rule_fixture::{四面とも同じ候補の規則, 壁をはめる候補, 規則と種で展開する};
use super::placement_table::部品ごとの配置表;

/// 4面すべてへ平壁を必ず入れる規則。候補を1つだけにして、どの種でも4枚が同じ位置へ据わるようにする。
fn 四面すべてに平壁を入れた配置表() -> 部品ごとの配置表 {
    規則と種で展開する(&四面とも同じ候補の規則(vec![壁をはめる候補("平壁")]), 1)
}

/// はめ口の宣言の順(正面・背面・左面・右面)に据わった壁の配置を引く。根の骨格が0番であるため1つずらす。
fn 面ごとの壁の配置() -> Vec<blitz_engine::個体配置> {
    let 配置表 = 四面すべてに平壁を入れた配置表();
    配置表
        .据えた順()
        .iter()
        .filter(|据えた| 据えた.識別子() == &識別子("平壁"))
        .map(|据えた| 据えた.配置())
        .collect()
}

fn 平行移動が近いか(得た: [f32; 3], 期待: [f32; 3]) -> bool {
    得た.iter().zip(期待).all(|(得, 期)| (得 - 期).abs() < 1.0e-5)
}

/// 壁の原点は、はめ口の面の中心から食い込ませる量だけ内側へ寄った点である。壁の外枠が壁の原点の真上
/// (高さ1.3)にあり、はめ口も高さ1.3にあるため、高さの成分は打ち消し合って0になる。
#[test]
fn 四面の壁が骨格の各面へ食い込んで据わる() {
    let 期待一覧 = [[0.0, 0.0, 0.98], [0.0, 0.0, -0.98], [-0.98, 0.0, 0.0], [0.98, 0.0, 0.0]];
    for (配置, 期待) in 面ごとの壁の配置().iter().zip(期待一覧) {
        assert!(
            平行移動が近いか(配置.平行移動(), 期待),
            "得た平行移動: {:?} 期待: {期待:?}",
            配置.平行移動()
        );
    }
}

/// 一致の様式は接合面の実寸がそろう比を導く。はめ口も外枠も2.00かける2.60であるため、比はちょうど1になる。
#[test]
fn 壁の倍率は一になる() {
    for 配置 in 面ごとの壁の配置() {
        assert_eq!(配置.スケール(), [1.0, 1.0, 1.0], "得た倍率: {:?}", 配置.スケール());
    }
}

/// 4面の壁が天頂軸まわりだけに回る。天頂軸以外の成分が立つと、壁が横倒しか前傾している。
#[test]
fn 壁は天頂軸まわりだけに回る() {
    for 配置 in 面ごとの壁の配置() {
        let 回転 = 配置.回転();
        assert!(回転[0].abs() < 1.0e-4 && 回転[2].abs() < 1.0e-4, "天頂軸以外の成分が立っている: {回転:?}");
    }
}

/// 正面が半回転・背面が恒等・左面が4分の1回転・右面が逆向きの4分の1回転である。
/// 天頂軸まわりの成分と実部の大きさで角度を、その積の符号で回る向きを見る。符号を反転した同値の表し方でも
/// 積の符号は変わらないため、この判定はクォータニオンの符号の取り方に依らない。
#[test]
fn 四面の壁が四分の一回転ずつ違う向きへ立つ() {
    let 四分の一 = std::f32::consts::FRAC_PI_4.sin();
    let 期待一覧 = [(1.0_f32, 0.0_f32), (0.0, 1.0), (四分の一, 四分の一), (-四分の一, 四分の一)];
    for (配置, (期待の天頂軸, 期待の実部)) in 面ごとの壁の配置().iter().zip(期待一覧) {
        let 回転 = 配置.回転();
        let 向きをそろえる = if 回転[3] * 期待の実部 + 回転[1] * 期待の天頂軸 < 0.0 {
            -1.0
        } else {
            1.0
        };
        assert!(
            (回転[1] * 向きをそろえる - 期待の天頂軸).abs() < 1.0e-4 && (回転[3] * 向きをそろえる - 期待の実部).abs() < 1.0e-4,
            "得た回転: {回転:?} 期待: 天頂軸{期待の天頂軸}・実部{期待の実部}"
        );
    }
}
