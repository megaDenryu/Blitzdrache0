//! 壁の外面へ差し込んだ飾りの上へ、さらに積み足す部品1つ。担当するのは、積み足す部品と上下の接合点の名前を
//! 保持することと、直前に据えた部品を親にした接合の指示へ写すことである。
//!
//! **煙突がこれを要求した初めての部品である。** 煙突は1段目を壁の外面へ包含で差し込み、2段目からは自分の上面へ
//! 一致で積む。飾りが葉のままでは、壁より高く伸びるものを表せない。
//!
//! 飾りそのもの(`frame_ornament`)から分けるのは、変わる理由が違うためである。飾りは壁が何を受けるかを決め、
//! この型は据わった部品が次の部品をどう受けるかを決める。
//!
//! **親を「直前に据えた部品」に固定し、番号で指させない。** まだ据わっていない部品を指す宣言を型で書けなく
//! するためであり、骨格の継ぎ足しが繋ぐ相手を直前の骨格に固定しているのと同じ規律である。表せるのは連なりだけに
//! なるが、枝分かれして伸びる飾りを要求する部品はまだ実物になっていない。
//! 積層は面が向かい合う隣接であるため、`法線方向のずらし`は煙突では零である。
//! 参照: `_doc/設計/部品カタログと接合点.md`「壁が外面の取付面を持つ(2026-08-19、Blitzdrache0Assetsの7fc2498)」

use crate::joint::{接合点名, 接合面上の位置, 法線方向のずらし};

use super::super::part::部品ID;
use super::instruction::{据えた部品の番号, 接合の指示};

#[derive(Debug, Clone, PartialEq)]
pub struct 飾りの上へ積み足す部品 {
    親の接合点: 接合点名, // 直前に据えた部品の側の接合点。煙突では上面積層
    部品: 部品ID,
    子の接合点: 接合点名,               // 積み足す部品の側の接合点。煙突では下面積層
    法線方向のずらし: 法線方向のずらし, // 直前に据えた部品の面へ食い込ませる量
}

impl 飾りの上へ積み足す部品 {
    pub fn 生成する(
        親の接合点: 接合点名, 部品: 部品ID, 子の接合点: 接合点名, 法線方向のずらし: 法線方向のずらし
    ) -> Self {
        Self {
            親の接合点,
            部品,
            子の接合点,
            法線方向のずらし,
        }
    }

    /// 直前に据えた部品を親にして積み足す指示。**一致の様式であるため、面上の位置は中心のほかに置きようがない。**
    pub(super) fn 指示にする(&self, 直前に据えた部品: 据えた部品の番号) -> 接合の指示 {
        接合の指示 {
            親: 直前に据えた部品,
            親の接合点: self.親の接合点.clone(),
            子の部品: self.部品.clone(),
            子の接合点: self.子の接合点.clone(),
            面上の位置: 接合面上の位置::中心(),
            法線方向のずらし: self.法線方向のずらし,
        }
    }
}
