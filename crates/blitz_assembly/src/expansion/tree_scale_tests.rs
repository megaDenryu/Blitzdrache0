//! 木の倍率と高さの試験。担当するのは、幹が節ごとに接合の導いた比で細くなることと、節の高さがその比で
//! 縮んだ丈の累和になることと、枝と葉房と冠が付いた先と同じ倍率になることを固定することである。
//!
//! **0.8をこの試験に書かない。** 幹頂部の直径0.4を幹基部の直径0.5で割った比として書き、規則にも試験にも
//! 太さの数が現れない形を保つ。部品の員数の試験は`tree_shape_tests`が持つ。

#![allow(clippy::unwrap_used)]

use super::tree_rule_fixture::樫の木を展開する;

/// 幹の一節の頂部の直径を、幹の一節の基部の直径で割った比。1節ごとに木がこれだけ細くなる。
const 一節ごとの比: f32 = 0.4 / 0.5;

/// 幹の一節の丈。実データの幹頂部が高さ2.0にあることから決まる。
const 一節の丈メートル: f32 = 2.0;

fn 倍率が近いか(倍率: [f32; 3], 期待: f32) -> bool {
    倍率.iter().all(|成分| (成分 - 期待).abs() < 1.0e-5)
}

/// 幹は上へ行くほど細くなる。比は接合が導いた値であり、節ごとに掛け合わされる。
#[test]
fn 幹は節ごとに接合が導いた比で細くなる() {
    let 配置表 = 樫の木を展開する(3);
    for (節, 期待) in [1.0, 一節ごとの比, 一節ごとの比 * 一節ごとの比].into_iter().enumerate() {
        let 倍率 = 配置表.据えた順()[節].配置().スケール();
        assert!(倍率が近いか(倍率, 期待), "{節}節目の倍率: {倍率:?}");
    }
}

/// 幹は上へ積み上がる。1節の丈が節ごとに比の分だけ縮むため、節の下端の高さはその累和になる。
#[test]
fn 幹の節の高さは細くなった丈の累和になる() {
    let 配置表 = 樫の木を展開する(3);
    let 期待の高さ = [0.0, 一節の丈メートル, 一節の丈メートル + 一節の丈メートル * 一節ごとの比];
    for (節, 期待) in 期待の高さ.into_iter().enumerate() {
        let 高さ = 配置表.据えた順()[節].配置().平行移動()[1];
        assert!((高さ - 期待).abs() < 1.0e-5, "{節}節目の高さ: {高さ}");
    }
}

/// 枝は根の節の側面へ付き、葉房は枝の先へ付く。どちらも付いた先と同じ倍率になり、根の節では1のままである。
/// 据えた順は幹を全部積んでから節ごとの枝と葉房が続くため、3番目が根の節の枝、4番目がその先の葉房である。
#[test]
fn 枝と葉房は付いた先と同じ倍率になる() {
    let 配置表 = 樫の木を展開する(3);
    for 添字 in [3, 4] {
        let 倍率 = 配置表.据えた順()[添字].配置().スケール();
        assert!(倍率が近いか(倍率, 1.0), "{添字}番目の倍率: {倍率:?}");
    }
}

/// 冠は幹の最上節の頂部へ載る。高さは最上節の下端に細くなった丈を足した値であり、倍率は最上節と同じである。
#[test]
fn 冠は幹の頂の高さへ最上節と同じ倍率で載る() {
    let 配置表 = 樫の木を展開する(3);
    let 冠 = 配置表.据えた順().last().unwrap().配置();
    let 最上節の倍率 = 一節ごとの比 * 一節ごとの比;
    let 期待の高さ = 一節の丈メートル + 一節の丈メートル * 一節ごとの比 + 一節の丈メートル * 最上節の倍率;
    assert!((冠.平行移動()[1] - 期待の高さ).abs() < 1.0e-5, "冠の高さ: {:?}", 冠.平行移動());
    assert!(倍率が近いか(冠.スケール(), 最上節の倍率), "冠の倍率: {:?}", 冠.スケール());
}
