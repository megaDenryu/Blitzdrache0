//! 手順の組み手: 規則から手順を組み立てる途中の状態。据えた件数と選択の通し番号を持つ。
//!
//! 可変の状態を型の中へ閉じるのは、据えた件数と通し番号がずれると、指示が指す親と引く値の両方が狂うためである。
//! どちらも「1つ足すと1つ増える」という同じ規律で動くが、増える契機が違う。階を積むと件数だけが増え、
//! 壁面を1つ見ると通し番号だけが増える。両方をここが持つことで、増やし忘れが1箇所に閉じる。

use blitz_math::メートル;

use super::super::part::部品ID;
use super::generation_seed::{展開の用途, 生成の種};
use super::instruction::{据えた部品の番号, 接合の指示};
use super::wall_choice::{壁面の指定, 壁面の飾り};
use crate::joint::{接合点名, 接合面上の位置, 法線方向のずらし};

use super::house_rule::積む階;

pub(super) struct 手順の組み手 {
    種: 生成の種,
    指示一覧: Vec<接合の指示>,
    選択の通し番号: u64,
    /// 直前に積んだ階の番号。次の階はこの上へ乗る。
    ///
    /// 注意: 「直前に据えた部品」で代用してはならない。壁の飾りを先に足すと直前に据えたのは飾りになり、
    /// 次の階が飾りの上へ乗る。積む相手は飾りでなく階である。
    直前の階の番号: 据えた部品の番号,
}

impl 手順の組み手 {
    pub(super) fn 土台から始める(種: 生成の種) -> Self {
        Self {
            種,
            指示一覧: Vec::new(),
            選択の通し番号: 0,
            直前の階の番号: 据えた部品の番号::根(),
        }
    }

    /// 直前に積んだ階の上へ階を積み、その階の番号を返す。指示を1つ足すと据えた部品が1つ増える。
    pub(super) fn 階を積む(&mut self, 階: &積む階) -> 据えた部品の番号 {
        self.指示一覧.push(接合の指示 {
            親: self.直前の階の番号,
            親の接合点: 階.親の上面.clone(),
            子の部品: 階.部品.clone(),
            子の接合点: 階.自分の下面.clone(),
            面上の位置: 接合面上の位置::中心(),
            法線方向のずらし: 法線方向のずらし::寄せない(),
        });
        self.直前の階の番号 = 据えた部品の番号::番号から生成する(self.指示一覧.len());
        self.直前の階の番号
    }

    pub(super) fn 壁面の飾りを足す(&mut self, 壁面一覧: &[壁面の指定], 階の番号: 据えた部品の番号) {
        for 壁面 in 壁面一覧 {
            let 値 = self
                .種
                .混合の生成器を作る()
                .零以上一未満(self.選択の通し番号, 展開の用途::壁面の飾りの選択.番号());
            self.選択の通し番号 += 1;
            if let 壁面の飾り::付ける {
                部品,
                接合点,
                横のずらし,
                法線方向のずらし,
            } = 壁面.値から選ぶ(値)
            {
                self.飾りを1つ付ける(階の番号, 壁面.接合点(), 部品, 接合点, *横のずらし, *法線方向のずらし);
            }
        }
    }

    fn 飾りを1つ付ける(
        &mut self,
        階の番号: 据えた部品の番号,
        壁面の接合点: &接合点名,
        部品: &部品ID,
        接合点: &接合点名,
        横のずらし: メートル,
        法線方向のずらし: 法線方向のずらし,
    ) {
        let 面上の位置 = 接合面上の位置::生成する(横のずらし, メートル::生成する(0.0)).unwrap_or_else(|_| 接合面上の位置::中心());
        self.指示一覧.push(接合の指示 {
            親: 階の番号,
            親の接合点: 壁面の接合点.clone(),
            子の部品: 部品.clone(),
            子の接合点: 接合点.clone(),
            面上の位置,
            法線方向のずらし,
        });
    }

    /// 組み立てた指示の列を取り出して閉じる。以降この組み手は使えない。
    pub(super) fn 指示一覧へ畳む(self) -> Vec<接合の指示> {
        self.指示一覧
    }
}
