//! 骨格1つへ張る床の宣言。担当するのは、床を張るかどうかと、張るなら何をどの口へ噛み合わせるかを持つことと、
//! それを接合の指示へ写すことである。
//!
//! **床を種で引く候補にしないのは、床の有無が意匠の振れでなく、抜けが破れに見えるためである。** 壁は面ごとに
//! 平壁か窓壁か何も入れないかを引いて姿を変えるが、床が引かれなかった骨格は「床の抜けた家」になる。
//! 1階が土間で2階が床板という違いは骨格が連なりのどこに在るかで決まり、種では決まらない。したがって
//! 骨格ごとの宣言として持ち、`はめ口の指定`のような候補の並びを持たない。
//!
//! **骨格を据えたら必ず1枚張る形にもしない。** Blender側の正解表は、床を持つ組み立てを屋根つきの家2件だけとし、
//! 2段積みと2ベイの見本には床を含めていない。床は骨格に必然的に付随するものではない。
//!
//! 候補を引かないため用途番号を1つも使わず、床を宣言していない既存の世界では指示が1件も増えない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格と壁の対、扉の対」

use crate::joint::{接合点名, 接合面上の位置, 法線方向のずらし};

use super::super::part::部品ID;
use super::instruction::{据えた部品の番号, 接合の指示};

/// 骨格1つへ張る床。
#[derive(Debug, Clone, PartialEq)]
pub enum 骨格へ張る床 {
    張らない,
    /// 骨格の床のはめ口へ床板の外枠を噛み合わせる。**食い込ませる量を持たないのは、床のはめ口と床の外枠が
    /// 面の向かい合う隣接であり、重なる面をそもそも持たないためである。** 壁が0.02メートル食い込むのとは理由が違う。
    床を張る {
        部品: 部品ID,
        /// 骨格の側の接合点。土台の梁の上面にある。
        床のはめ口: 接合点名,
        /// 床板の側の接合点。床のはめ口と一致の様式で噛み合う。
        床の外枠: 接合点名,
    },
}

impl 骨格へ張る床 {
    /// 名指した骨格へ床を張る指示。張らない宣言では指示が1件も出ない。
    /// **一致の様式であるため、面上の位置は中心のほかに置きようがない。**
    pub(super) fn 指示にする(&self, 親: 据えた部品の番号) -> Option<接合の指示> {
        let Self::床を張る {
            部品, 床のはめ口, 床の外枠
        } = self
        else {
            return None;
        };
        Some(接合の指示 {
            親,
            親の接合点: 床のはめ口.clone(),
            子の部品: 部品.clone(),
            子の接合点: 床の外枠.clone(),
            面上の位置: 接合面上の位置::中心(),
            法線方向のずらし: 法線方向のずらし::寄せない(),
        })
    }
}
