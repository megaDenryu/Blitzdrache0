//! 壁1枚の外面へ何を差し込むかの選択肢。担当するのは候補を保持することと、0以上1未満の値から1つを選ぶことと、
//! 選んだ候補を接合の指示へ写すことである。
//!
//! **骨格方式で壁が何かを受けるのはこれが初めてである。** 段7の時点では骨格が壁を受けるだけで壁は葉であった。
//! 骨格から壁へ、壁から飾りへと2段に伸びるため、飾りの親は骨格でなく、いま据えたばかりの壁である。
//!
//! **一体型の家の`壁面の指定`を流用しないのは、あちらが横のずらしを持つためである。** 壁の外面の飾り取付は
//! 面の中心1つだけを使い、面に沿って滑らせる意匠の自由度を今は持たない。流用すると宣言が横のずらしを書ける形になる。
//! あわせて親が違う。あちらは一体の階の壁面へ差し込み、こちらは骨格へはめた壁1枚の外面へ差し込む。
//!
//! 候補が空の指定を拒むのは、選べない選択肢が「選んだ結果が無い」という半端な状態を作るためである。
//! **「何も付けない」を表したいなら、それを候補の1つとして並べる。** はめ口と節の枝と継ぎ足しと同じ様式である。
//! 参照: `_doc/設計/部品カタログと接合点.md`「壁が外面の取付面を持つ(2026-08-19、Blitzdrache0Assetsの7fc2498)」

use crate::joint::{接合点名, 接合面上の位置, 法線方向のずらし};

use super::super::part::部品ID;
use super::choice_index::添字へ写す;
use super::error_rule::規則エラー;
use super::instruction::{据えた部品の番号, 接合の指示};

/// 壁1枚の外面へ差し込むものの1つの候補。
#[derive(Debug, Clone, PartialEq)]
pub enum 壁の外面の飾り {
    付けない,
    /// 壁の外面の飾り取付へ、飾りの側の差込口を包含の様式で噛み合わせる。
    差し込む {
        部品: 部品ID,
        差込口: 接合点名,
        /// 壁の外面へ寄せる量。零で向かい合わせると面がぴったり接する。
        法線方向のずらし: 法線方向のずらし,
    },
}

impl 壁の外面の飾り {
    /// 名指した壁の名指した取付面へこの候補を差し込む指示。付けない候補では指示が1件も出ない。
    /// **面上の位置が中心なのは、この取付面が意匠のずらしを持たないためである。**
    pub(super) fn 指示にする(&self, 親: 据えた部品の番号, 飾り取付: &接合点名) -> Option<接合の指示> {
        let Self::差し込む {
            部品,
            差込口,
            法線方向のずらし,
        } = self
        else {
            return None;
        };
        Some(接合の指示 {
            親,
            親の接合点: 飾り取付.clone(),
            子の部品: 部品.clone(),
            子の接合点: 差込口.clone(),
            面上の位置: 接合面上の位置::中心(),
            法線方向のずらし: *法線方向のずらし,
        })
    }
}

/// 壁の外面の取付面1つと、そこへ差し込む候補の並び。
#[derive(Debug, Clone, PartialEq)]
pub struct 壁の外面の飾りの指定 {
    飾り取付: 接合点名,
    候補一覧: Vec<壁の外面の飾り>,
}

impl 壁の外面の飾りの指定 {
    pub fn 生成する(飾り取付: 接合点名, 候補一覧: Vec<壁の外面の飾り>) -> Result<Self, 規則エラー> {
        if 候補一覧.is_empty() {
            return Err(規則エラー::壁の外面の飾りの候補が空である {
                飾り取付の名前: 飾り取付
            });
        }
        Ok(Self { 飾り取付, 候補一覧 })
    }

    pub(super) fn 飾り取付(&self) -> &接合点名 {
        &self.飾り取付
    }

    /// 0以上1未満の値から候補を1つ選ぶ。候補が空でないことを生成の時点で確かめてあるため、必ず1つ選べる。
    pub(super) fn 値から選ぶ(&self, 零以上一未満: f32) -> &壁の外面の飾り {
        let 添字 = 添字へ写す(零以上一未満, self.候補一覧.len());
        match self.候補一覧.get(添字) {
            Some(候補) => 候補,
            None => panic!("候補が空でないという不変条件に違反した"),
        }
    }
}
