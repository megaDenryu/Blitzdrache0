//! 部品ごとの配置: 1つの部品と、その部品を置くすべての配置。**これがそのまま描画対象1つの単位になる。**
//!
//! 配置表から取り出す眺めと、複数の個体をまとめた集約の項目が同じ型であることが重要である。1軒だけ建てたときと
//! 100軒建てたときで描画側が受け取る形は変わらず、変わるのは配置列の長さだけである。
//!
//! 配置列を後から足せる口を持つのは、集約が同じ部品を何度も受け取るためである。足す口をこの型が持つことで、
//! 集約の側が部品IDと配置列の対応を裸の組で持ち回らずに済む。
//! 参照: `_doc/設計/部品カタログと接合点.md`「設計の核心」

use blitz_engine::個体配置;

use super::super::part::部品ID;

#[derive(Debug, Clone, PartialEq)]
pub struct 部品ごとの配置 {
    識別子: 部品ID,
    配置一覧: Vec<個体配置>,
}

impl 部品ごとの配置 {
    pub(super) fn 識別子から空で始める(識別子: 部品ID) -> Self {
        Self {
            識別子,
            配置一覧: Vec::new(),
        }
    }

    pub(super) fn 配置を1件足す(&mut self, 配置: 個体配置) {
        self.配置一覧.push(配置);
    }

    pub fn 識別子(&self) -> &部品ID {
        &self.識別子
    }

    pub fn 配置一覧(&self) -> &[個体配置] {
        &self.配置一覧
    }
}
