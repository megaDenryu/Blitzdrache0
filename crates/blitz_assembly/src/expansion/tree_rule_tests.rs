//! 木の規則の展開の試験。担当するのは、1本の木が幹の連鎖と枝と葉房になることと、段ごとに細くなる倍率が
//! 接合から導かれることと、同じ規則から2回展開した配置表が完全に一致することを固定することである。
//!
//! **0.8をこの試験にも書かない。** 幹頂部の直径0.4を幹基部の直径0.5で割った比として書き、
//! 規則にも試験にも太さの数が現れない形を保つ。材料は`tree_rule_fixture`が持つ。

#![allow(clippy::unwrap_used)]

use crate::tree_catalog_fixture::識別子;

use super::tree_rule::木の規則;
use super::tree_rule_fixture::{幹の指定を作る, 枝の指定を作る, 樫の木を展開する, 葉房の指定を作る};
use super::trunk_segment::{幹の節の番号, 幹の節数};

/// 幹の一節の頂部の直径を、幹の一節の基部の直径で割った比。1節ごとに木がこれだけ細くなる。
const 一節ごとの比: f32 = 0.4 / 0.5;

fn 倍率が近いか(倍率: [f32; 3], 期待: f32) -> bool {
    倍率.iter().all(|成分| (成分 - 期待).abs() < 1.0e-5)
}

#[test]
fn 一本の木は幹3節と枝と葉房になる() {
    let 配置表 = 樫の木を展開する(3);
    assert_eq!(配置表.配置の総数(), 5);
    assert_eq!(配置表.部品の種類数(), 3);
    let 幹の件数 = 配置表.据えた順().iter().filter(|据えた| 据えた.識別子() == &識別子("幹の一節")).count();
    assert_eq!(幹の件数, 3);
}

/// 幹は上へ行くほど細くなる。比は接合が導いた値であり、節ごとに掛け合わされる。
#[test]
fn 幹は節ごとに接合が導いた比で細くなる() {
    let 配置表 = 樫の木を展開する(3);
    for (節, 期待) in [1.0, 一節ごとの比, 一節ごとの比 * 一節ごとの比].into_iter().enumerate() {
        let 倍率 = 配置表.据えた順()[節].配置().スケール();
        assert!(倍率が近いか(倍率, 期待), "{節}節目の倍率: {倍率:?}");
    }
}

/// 幹は上へ積み上がる。1節の丈2.0が節ごとに比の分だけ縮むため、節の下端の高さはその累和になる。
#[test]
fn 幹の節の高さは細くなった丈の累和になる() {
    let 配置表 = 樫の木を展開する(3);
    let 期待の高さ = [0.0, 2.0, 2.0 + 2.0 * 一節ごとの比];
    for (節, 期待) in 期待の高さ.into_iter().enumerate() {
        let 高さ = 配置表.据えた順()[節].配置().平行移動()[1];
        assert!((高さ - 期待).abs() < 1.0e-5, "{節}節目の高さ: {高さ}");
    }
}

/// 枝は2節目の側面へ付き、葉房は枝の先へ付く。どちらも付いた先と同じだけ細くなる。
#[test]
fn 枝と葉房は付いた先と同じ倍率になる() {
    let 配置表 = 樫の木を展開する(3);
    for 添字 in [3, 4] {
        let 倍率 = 配置表.据えた順()[添字].配置().スケール();
        assert!(倍率が近いか(倍率, 一節ごとの比), "{添字}番目の倍率: {倍率:?}");
    }
}

/// 平行移動も回転も倍率も含めて一致することを見る。平行移動だけを比べると、回転だけが揺れる形の破れを見逃す。
#[test]
fn 同じ規則からの2回の展開は完全に一致する() {
    assert_eq!(樫の木を展開する(3), 樫の木を展開する(3));
}

/// 幹より高い節から枝を生やす規則を拒む。据わっていない節を親に指す手順は、展開の途中で初めて落ちる。
#[test]
fn 幹より高い節から枝を生やす規則を拒む() {
    let 誤り = 木の規則::生成する(
        幹の指定を作る(),
        幹の節数::生成する(1).unwrap(),
        幹の節の番号::生成する(2).unwrap(),
        枝の指定を作る(),
        葉房の指定を作る(),
    );
    assert!(誤り.is_err());
}
