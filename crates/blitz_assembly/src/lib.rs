//! 部品の接合と組み立ての層。担当するのは、接合点の語彙・部品カタログ・組み立て規則・展開器である。
//!
//! 知ってよいのは`blitz_engine`(個体配置)と`blitz_math`だけである。glTFもファイルシステムも実行時形式も知らない。
//! この「知らない」をクレート境界で守るのは、同じクレートの中では`use gltf::...`と書いた瞬間に通ってしまい、
//! 文書に書いた境界が境界にならないためである。依存は`cargo xtask conform`の依存白リストが検査する。
//!
//! 接合点をglTFから読む工程は`blitz_asset_compiler`の`loader`が持ち、そこで作られた値がこの層へ入ってくる。
//! この層は読み方を知らず、読む側はこの層の型だけを作る。
//!
//! 層の中は4つに分かれる。`joint`が接合点の語彙、`part`が部品とカタログ、`mating`が1つの噛み合わせの計算、
//! `expansion`が規則からの展開と、何軒ぶんもの展開を部品ごとにまとめる集約である。
//! 参照: `_doc/設計/部品カタログと接合点.md`「層と依存の向き」

#![forbid(unsafe_code)]

mod expansion;
mod joint;
mod mating;
mod part;

#[cfg(test)]
