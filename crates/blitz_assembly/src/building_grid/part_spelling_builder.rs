//! 骨格方式の部品の綴りの組み手: 役割ごとに部品の識別子を1つずつ預かり、8つ揃ってから綴りを完成させる型。
//!
//! 完成した型(`part_spelling`)から分けるのは、呼び出し頻度と呼び出しの時機が違うためである。組み手は
//! カタログを読み終えた1度だけ動き、綴りは升目を写すたびに引かれる。
//!
//! 預かりを配列で持って役割で名指すのは、8つの識別子を引数で並べる口が、平壁と窓壁を取り違えて渡しても
//! 型を通してしまうためである。役割で名指せば取り違えが書けない。

use crate::part::部品ID;

use super::error::ベイ格子エラー;
use super::part_role::骨格方式の部品の役割;
use super::part_spelling::骨格方式の部品の綴り;

pub struct 骨格方式の部品の綴りの組み手 {
    役割ごとの預かり: [Option<部品ID>; 8],
}

impl 骨格方式の部品の綴りの組み手 {
    pub fn 空から始める() -> Self {
        Self {
            役割ごとの預かり: std::array::from_fn(|_| None),
        }
    }

    /// 同じ役割へ2度預けると後の識別子が残る。どちらが正しいかを型が決められないため、拒まずに上書きする。
    pub fn 部品を1つ定める(&mut self, 役割: 骨格方式の部品の役割, 識別子: 部品ID) {
        if let Some(預かり) = self.役割ごとの預かり.get_mut(役割.添字()) {
            *預かり = Some(識別子);
        }
    }

    /// 8つの役割が揃っていれば綴りを完成させ、欠けていれば最初に見つけた役割を名指して拒む。
    /// **既定の綴りで黙って埋めない。** どの部品を使うかはBlender側の名前で決まり、この層は知らない。
    pub fn 綴りを閉じる(mut self) -> Result<骨格方式の部品の綴り, ベイ格子エラー> {
        let 全役割 = 骨格方式の部品の役割::全役割を数え上げる();
        let mut 揃った並び = Vec::with_capacity(全役割.len());
        for 役割 in 全役割 {
            match self.役割ごとの預かり.get_mut(役割.添字()).and_then(Option::take) {
                Some(識別子) => 揃った並び.push(識別子),
                None => return Err(ベイ格子エラー::部品の綴りが定まっていない { 役割 }),
            }
        }
        match <[部品ID; 8]>::try_from(揃った並び) {
            Ok(並び) => Ok(骨格方式の部品の綴り::揃った並びから生成する(並び)),
            Err(_) => panic!("役割の数え上げの件数と綴りの表の長さが食い違っている"),
        }
    }
}
