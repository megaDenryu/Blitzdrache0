//! 骨格方式の部品の綴り: 8つの役割それぞれに部品の識別子が定まった表。
//!
//! 綴りを格子の側が持たず呼び出し側から預かるのは、Blender側が部品へ与えた名前の正本が
//! `crates/blitz_asset_compiler/examples/part_assembly/frame_bay_spelling.rs`にあるためである。
//! ここへ綴りを書くと正本が2つになり、片方だけを直した食い違いが焼くまで出ない。
//!
//! 生成の口を持たず組み手を通してのみ作れるのは、8つの役割が揃うまで「どの役割が欠けているか」を
//! 判定できないためである。半端な状態を完成した型へ漏らさない口をここへ1つだけ置く。

use crate::part::部品ID;

use super::part_role::骨格方式の部品の役割;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 骨格方式の部品の綴り {
    役割ごとの識別子: [部品ID; 8],
}

impl 骨格方式の部品の綴り {
    /// 組み手が8つの役割の充足を確かめてから呼ぶ口。並びの添字は役割の添字である。
    pub(super) fn 揃った並びから生成する(役割ごとの識別子: [部品ID; 8]) -> Self {
        Self { 役割ごとの識別子 }
    }

    /// 名指した役割の部品の識別子。8つとも定まっていることを生成の時点で確かめてあるため、必ず1つ答える。
    pub fn 役割から部品の識別子を引く(&self, 役割: 骨格方式の部品の役割) -> &部品ID {
        match self.役割ごとの識別子.get(役割.添字()) {
            Some(識別子) => 識別子,
            None => panic!("役割の添字が綴りの表の長さを超えた。役割の数え上げと表の長さが食い違っている"),
        }
    }
}
