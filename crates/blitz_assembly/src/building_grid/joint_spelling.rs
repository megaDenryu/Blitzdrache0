//! 面に属さない接合点の綴りの正本。骨格の上下の積層の口と床のはめ口、床板と屋根と壁が向かい合わせる口を
//! この1箇所だけが持つ。側面が持つ2つの口の綴りは`side_face`が、飾りの側の口は`ornament`が持つ。
//!
//! 綴りを工程ごとに書くと、Blender側が名前を改めたときに1つだけ直し忘れる形の食い違いが起きる。
//!
//! 綴りから値を作る口が失敗を返さないのは、渡すのが定数であり空になりようがないためである。
//! 空を渡せるのは定数を書き換えたときだけであり、それは到達したらプログラムの誤りである。

use crate::joint::接合点名;

/// 骨格が上へ積む相手へ向ける口。屋根もここへ載る。
pub(super) fn 骨格の上面の接合点名() -> 接合点名 {
    接合点名を作る("骨格の上面")
}

pub(super) fn 骨格の下面の接合点名() -> 接合点名 {
    接合点名を作る("骨格の下面")
}

/// 骨格が土台の梁の上面へ宣言する、床板を受ける口。
pub(super) fn 床のはめ口の接合点名() -> 接合点名 {
    接合点名を作る("床のはめ口")
}

pub(super) fn 床の外枠の接合点名() -> 接合点名 {
    接合点名を作る("床の外枠")
}

pub(super) fn 屋根の下面の接合点名() -> 接合点名 {
    接合点名を作る("屋根の下面")
}

/// 壁3種が共通で持つ、骨格のはめ口と噛み合う接合点の名前。
pub(super) fn 壁の外枠の接合点名() -> 接合点名 {
    接合点名を作る("壁の外枠")
}

/// 壁3種が共通で持つ、外面の中心の取付面。外枠の裏側にあたり、法線が外を向く。
pub(super) fn 壁の外面の飾り取付の接合点名() -> 接合点名 {
    接合点名を作る("外面の飾り取付")
}

pub(super) fn 接合点名を作る(綴り: &str) -> 接合点名 {
    match 接合点名::生成する(綴り) {
        Ok(名前) => 名前,
        Err(_) => panic!("骨格方式の接合点の綴りが空である。定数を書き換えたときにしか起こらない"),
    }
}
