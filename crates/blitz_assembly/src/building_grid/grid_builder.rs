//! ベイ格子の組み手: 升目を1つずつ置き、全部が揃ってから検査して格子を完成させる型。
//!
//! 完成した格子(`grid`)から分けるのは、呼び出しの時機が違うためである。組み手は人が升目を置くたびに動き、
//! 格子は組み立て手順を作るときに動く。
//!
//! 最初に置いた升目を覚えるのは、根を人が選ばなかったときの既定にするためである。既定を「座標の最も小さい
//! 升目」にしないのは、人が最初に置いた升目が建物の起点であるという編集の実感と合わないためである。

use super::cell::升目の宣言;
use super::cell_coordinate::升目の座標;
use super::cell_table::升目の表;
use super::error::ベイ格子エラー;
use super::grid::ベイ格子;
use super::grid_validation::宣言の破れを拒む;
use super::spanning_tree::升目をつなぐ木;

pub struct ベイ格子の組み手 {
    升目の表: 升目の表,
    最初に置いた升目: Option<升目の座標>,
}

impl ベイ格子の組み手 {
    pub fn 空から始める() -> Self {
        Self {
            升目の表: 升目の表::空から始める(),
            最初に置いた升目: None,
        }
    }

    /// 名指した座標へ升目を1つ置く。同じ座標へ2度置くのは型付きエラーで拒む。
    pub fn 升目を1つ置く(&mut self, 座標: 升目の座標, 宣言: 升目の宣言) -> Result<(), ベイ格子エラー> {
        self.升目の表.升目を1つ置く(座標, 宣言)?;
        if self.最初に置いた升目.is_none() {
            self.最初に置いた升目 = Some(座標);
        }
        Ok(())
    }

    /// 最初に置いた升目を根にして閉じる。1つも置いていなければ型付きエラーで拒む。
    pub fn 最初に置いた升目を根にして閉じる(self) -> Result<ベイ格子, ベイ格子エラー> {
        let Some(根) = self.最初に置いた升目 else {
            return Err(ベイ格子エラー::升目が1つも無い);
        };
        self.根を定めて閉じる(根)
    }

    /// 人が選んだ升目を根にして閉じる。宣言の破れと、根から到達できない升目を型付きエラーで拒む。
    pub fn 根を定めて閉じる(self, 根: 升目の座標) -> Result<ベイ格子, ベイ格子エラー> {
        if self.升目の表.空か() {
            return Err(ベイ格子エラー::升目が1つも無い);
        }
        宣言の破れを拒む(&self.升目の表)?;
        let つなぐ木 = 升目をつなぐ木::根から張る(&self.升目の表, 根)?;
        Ok(ベイ格子::検査を終えた材料から生成する(self.升目の表, 根, つなぐ木))
    }
}
