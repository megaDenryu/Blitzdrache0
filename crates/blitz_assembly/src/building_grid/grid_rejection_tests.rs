//! ベイ格子が拒む升目の並びの試験。担当するのは、破れた宣言と繋がらない並びが完成した格子にならないことを
//! 固定することである。値そのものの破れは`value_rejection_tests`が、手順の姿は`grid_recipe_tests`が持つ。
//!
//! 拒む形を1件ずつ固定するのは、検査を1つ落としたときに「拒まれるはずのものが通る」ことが、
//! 焼いた絵の中の宙に浮いた骨格や隣のベイの中に立つ壁として初めて見えるためである。

#![allow(clippy::unwrap_used)]

use super::cell::升目の宣言;
use super::cell_coordinate::升目の座標;
use super::cell_horizontal_face::升目の屋根;
use super::error::ベイ格子エラー;
use super::grid_builder::ベイ格子の組み手;
use super::grid_fixture::{四面へ平壁を入れた升目, 左面を空けた升目};
use super::side_face::升目の側面;

fn 升目の並びを閉じた誤り(升目の並び: &[(升目の座標, 升目の宣言)]) -> ベイ格子エラー {
    let mut 組み手 = ベイ格子の組み手::空から始める();
    for (座標, 宣言) in 升目の並び {
        組み手.升目を1つ置く(*座標, *宣言).unwrap();
    }
    組み手.最初に置いた升目を根にして閉じる().unwrap_err()
}

#[test]
fn 升目が1つも無い格子を拒む() {
    let 誤り = ベイ格子の組み手::空から始める().最初に置いた升目を根にして閉じる().unwrap_err();
    assert_eq!(誤り, ベイ格子エラー::升目が1つも無い);
}

/// 離れて置いた升目は隣接でも上下でも根と繋がらず、木の枝を伸ばす先が無い。
#[test]
fn 根から到達できない升目を拒む() {
    let 座標 = 升目の座標::生成する(5, 0, 0);
    let 誤り = 升目の並びを閉じた誤り(&[
        (升目の座標::生成する(0, 0, 0), 四面へ平壁を入れた升目()),
        (座標, 四面へ平壁を入れた升目()),
    ]);
    assert_eq!(誤り, ベイ格子エラー::根から到達できない升目がある { 座標 });
}

/// 隣の升目がある面は隣を継ぐ口として使われる。同じ面へ壁を入れると隣のベイの中に壁が1枚立つ。
#[test]
fn 隣の升目がある側面へ壁を入れるのを拒む() {
    let 座標 = 升目の座標::生成する(0, 0, 0);
    let 側面 = 升目の側面::右面;
    let 誤り = 升目の並びを閉じた誤り(&[(座標, 四面へ平壁を入れた升目()), (升目の座標::生成する(1, 0, 0), 左面を空けた升目())]);
    assert_eq!(誤り, ベイ格子エラー::隣の升目がある側面へ壁を入れている { 座標, 側面 });
}

/// 真下の升目が無い階は宙に浮く。階を積む口が向かい合う相手を持たない。
#[test]
fn 真下に升目の無い階を拒む() {
    let 座標 = 升目の座標::生成する(0, 0, 1);
    let 誤り = 升目の並びを閉じた誤り(&[(座標, 四面へ平壁を入れた升目())]);
    assert_eq!(誤り, ベイ格子エラー::真下に升目が無い { 座標 });
}

#[test]
fn 同じ座標へ升目を二重に置くのを拒む() {
    let 座標 = 升目の座標::生成する(0, 0, 0);
    let mut 組み手 = ベイ格子の組み手::空から始める();
    組み手.升目を1つ置く(座標, 四面へ平壁を入れた升目()).unwrap();
    let 誤り = 組み手.升目を1つ置く(座標, 四面へ平壁を入れた升目()).unwrap_err();
    assert_eq!(誤り, ベイ格子エラー::同じ座標へ升目を二重に置いた { 座標 });
}

/// 骨格の上面は上の階を積む口と同じ面である。両方を使うと上の階の中へ屋根が1つ入る。
#[test]
fn 真上に升目がある升目へ屋根を載せるのを拒む() {
    let 座標 = 升目の座標::生成する(0, 0, 0);
    let 誤り = 升目の並びを閉じた誤り(&[
        (座標, 四面へ平壁を入れた升目().屋根を定める(升目の屋根::載せる)),
        (升目の座標::生成する(0, 0, 1), 四面へ平壁を入れた升目()),
    ]);
    assert_eq!(誤り, ベイ格子エラー::真上に升目がある升目へ屋根を載せている { 座標 });
}

#[test]
fn 根に指した升目が格子に無いのを拒む() {
    let 座標 = 升目の座標::生成する(9, 9, 0);
    let mut 組み手 = ベイ格子の組み手::空から始める();
    組み手.升目を1つ置く(升目の座標::生成する(0, 0, 0), 四面へ平壁を入れた升目()).unwrap();
    let 誤り = 組み手.根を定めて閉じる(座標).unwrap_err();
    assert_eq!(誤り, ベイ格子エラー::根に指した升目が格子に無い { 座標 });
}
