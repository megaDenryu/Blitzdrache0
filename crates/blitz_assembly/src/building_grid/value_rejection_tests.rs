//! 値そのものが拒む形の試験。担当するのは、煙突の段数と部品の綴りが半端なまま完成した値にならないことを
//! 固定することである。升目の並びが拒む形は`grid_rejection_tests`が持つ。
//!
//! 升目の並びの試験と分けるのは、破れが見つかる時機が違うためである。こちらは値を1つ作った時点で決まり、
//! あちらは升目が揃って格子を閉じるまで決まらない。

#![allow(clippy::unwrap_used)]

use crate::part::部品ID;

use super::error::ベイ格子エラー;
use super::ornament::煙突の段数;
use super::part_role::骨格方式の部品の役割;
use super::part_spelling_builder::骨格方式の部品の綴りの組み手;

/// 壁の外面へ立てる以上、1段目は必ずある。零段の煙突は「立てるのに1段も無い」という半端な状態である。
#[test]
fn 段数が零の煙突を拒む() {
    assert_eq!(煙突の段数::生成する(0).unwrap_err(), ベイ格子エラー::煙突の段数が零である);
}

/// 8つの役割のどれか1つでも綴りが定まっていなければ、既定で埋めずに欠けた役割を名指して拒む。
#[test]
fn 綴りの定まらない役割がある部品の綴りを拒む() {
    let mut 組み手 = 骨格方式の部品の綴りの組み手::空から始める();
    組み手.部品を1つ定める(骨格方式の部品の役割::骨格, 部品ID::生成する("一間四方の骨格").unwrap());
    let 役割 = 骨格方式の部品の役割::平壁;
    assert_eq!(組み手.綴りを閉じる().unwrap_err(), ベイ格子エラー::部品の綴りが定まっていない { 役割 });
}

/// 同じ役割へ2度預けると後の綴りが残る。どちらが正しいかを型が決められないためである。
#[test]
fn 同じ役割へ二度預けると後の綴りが残る() {
    let mut 組み手 = 骨格方式の部品の綴りの組み手::空から始める();
    for (役割, 綴り) in [
        (骨格方式の部品の役割::骨格, "古い骨格"),
        (骨格方式の部品の役割::骨格, "新しい骨格"),
        (骨格方式の部品の役割::平壁, "平壁"),
        (骨格方式の部品の役割::窓壁, "窓壁"),
        (骨格方式の部品の役割::扉枠付きの壁, "扉枠付きの壁"),
        (骨格方式の部品の役割::切妻屋根, "切妻屋根"),
        (骨格方式の部品の役割::床板, "床板"),
        (骨格方式の部品の役割::出窓, "出窓"),
        (骨格方式の部品の役割::煙突セグメント, "煙突"),
    ] {
        組み手.部品を1つ定める(役割, 部品ID::生成する(綴り).unwrap());
    }
    let 綴り = 組み手.綴りを閉じる().unwrap();
    assert_eq!(綴り.役割から部品の識別子を引く(骨格方式の部品の役割::骨格).綴り(), "新しい骨格");
}
