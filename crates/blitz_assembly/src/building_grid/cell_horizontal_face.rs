//! 升目の2つの水平な面の宣言。下を向く床のはめ口へ床板を張るかと、上を向く骨格の上面へ屋根を載せるかである。
//!
//! 側面の宣言(`opening_fill`)から分けるのは、受ける相手が違うためである。側面は壁を受けて、その壁がさらに
//! 飾りを受ける。水平な面が受ける床板と屋根はどちらも葉であり、その上へ継げるものを持たない。
//!
//! 床を選べる宣言にしているのは、1階が土間で2階が床板という違いが人の編集で決まるためである。
//! 屋根を載せられるのは真上に升目の無い升目だけであり、その検査は格子の側が持つ。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格へ床を張る(2026-08-19、Blitzdrache0Assetsの581e409)」

use crate::expansion::{据えた部品の番号, 接合の指示};
use crate::joint::{接合面上の位置, 法線方向のずらし};

use super::joint_spelling::{
    屋根の下面の接合点名, 床のはめ口の接合点名, 床の外枠の接合点名, 骨格の上面の接合点名
};
use super::part_role::骨格方式の部品の役割;
use super::part_spelling::骨格方式の部品の綴り;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 升目の床 {
    張らない,
    張る,
}

impl 升目の床 {
    /// 名指した骨格の床のはめ口へ床板の外枠を噛み合わせる指示。張らない宣言では指示が1件も出ない。
    /// 寄せないのは、床のはめ口と床の外枠が面の向かい合う隣接であり、重なる面をそもそも持たないためである。
    pub(super) fn 床板を張る指示(self, 綴り: &骨格方式の部品の綴り, 親: 据えた部品の番号) -> Option<接合の指示> {
        match self {
            Self::張らない => None,
            Self::張る => Some(接合の指示 {
                親,
                親の接合点: 床のはめ口の接合点名(),
                子の部品: 綴り.役割から部品の識別子を引く(骨格方式の部品の役割::床板).clone(),
                子の接合点: 床の外枠の接合点名(),
                面上の位置: 接合面上の位置::中心(),
                法線方向のずらし: 法線方向のずらし::寄せない(),
            }),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 升目の屋根 {
    載せない,
    載せる,
}

impl 升目の屋根 {
    pub(super) fn 載せるか(self) -> bool {
        matches!(self, Self::載せる)
    }

    /// 名指した骨格の上面へ切妻屋根の下面を載せる指示。載せない宣言では指示が1件も出ない。
    pub(super) fn 屋根を載せる指示(self, 綴り: &骨格方式の部品の綴り, 親: 据えた部品の番号) -> Option<接合の指示> {
        match self {
            Self::載せない => None,
            Self::載せる => Some(接合の指示 {
                親,
                親の接合点: 骨格の上面の接合点名(),
                子の部品: 綴り.役割から部品の識別子を引く(骨格方式の部品の役割::切妻屋根).clone(),
                子の接合点: 屋根の下面の接合点名(),
                面上の位置: 接合面上の位置::中心(),
                法線方向のずらし: 法線方向のずらし::寄せない(),
            }),
        }
    }
}
