//! 骨格方式の部品の役割: ベイ格子が組み立てに使う部品の種類。骨格1件と壁3種と切妻屋根と床板と出窓と煙突である。
//!
//! 役割を型で数え上げるのは、部品の綴りを預かる表が8つの識別子を同じ型で並べる形になるためである。
//! 同じ型の並びは、平壁と窓壁を取り違えて渡しても型が通る。役割で名指して預ければ取り違えが書けない。
//!
//! 綴りそのものをここが持たないのは、Blender側が部品へ与えた名前の正本が
//! `crates/blitz_asset_compiler/examples/part_assembly/frame_bay_spelling.rs`にあるためである。
//! この層は役割の数え上げだけを持ち、どの綴りがどの役割かは呼び出し側が決める。

use std::fmt;

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum 骨格方式の部品の役割 {
    骨格,
    平壁,
    窓壁,
    扉枠付きの壁,
    切妻屋根,
    床板,
    出窓,
    煙突セグメント,
}

/// 綴りの表の格納順であり、組み立ての順序ではない。不足の報告がこの順で並ぶ。
const 全役割: [骨格方式の部品の役割; 8] = [
    骨格方式の部品の役割::骨格,
    骨格方式の部品の役割::平壁,
    骨格方式の部品の役割::窓壁,
    骨格方式の部品の役割::扉枠付きの壁,
    骨格方式の部品の役割::切妻屋根,
    骨格方式の部品の役割::床板,
    骨格方式の部品の役割::出窓,
    骨格方式の部品の役割::煙突セグメント,
];

impl 骨格方式の部品の役割 {
    pub(super) fn 全役割を数え上げる() -> [Self; 8] {
        全役割
    }

    /// 綴りの表の中でこの役割が占める位置。表を配列で持つため、役割から位置が一意に決まることが要る。
    pub(super) fn 添字(self) -> usize {
        match self {
            Self::骨格 => 0,
            Self::平壁 => 1,
            Self::窓壁 => 2,
            Self::扉枠付きの壁 => 3,
            Self::切妻屋根 => 4,
            Self::床板 => 5,
            Self::出窓 => 6,
            Self::煙突セグメント => 7,
        }
    }

    fn 呼び名(self) -> &'static str {
        match self {
            Self::骨格 => "骨格",
            Self::平壁 => "平壁",
            Self::窓壁 => "窓壁",
            Self::扉枠付きの壁 => "扉枠付きの壁",
            Self::切妻屋根 => "切妻屋根",
            Self::床板 => "床板",
            Self::出窓 => "出窓",
            Self::煙突セグメント => "煙突セグメント",
        }
    }
}

impl fmt::Display for 骨格方式の部品の役割 {
    fn fmt(&self, 出力: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(出力, "{}", self.呼び名())
    }
}
