//! 升目をつなぐ木: 根から幅優先で全升目へ張った木。指示を組む工程はこの並びの順に升目を組む。
//!
//! 木を組み手が張って格子へ持たせるのは、親を指す参照を解決し終えた形だけを完成した格子に残すためである。
//! 座標のまま親を指すと、指した先が格子に無い升目でも型が通り、その破れが展開の「親がまだ据わっていない」
//! という遠い場所の失敗になる。
//!
//! 幅優先にするのは、根に近い升目から順に据わる並びが人の直感と合うためであり、深さ優先と違って
//! 木の深さが増えても走査が積み上がらないためである。

use std::collections::BTreeSet;

use super::cell_coordinate::升目の座標;
use super::cell_table::升目の表;
use super::error::ベイ格子エラー;
use super::tree_link::親からの継ぎ方;
use super::tree_node::木に張った升目;

#[derive(Debug, Clone, PartialEq, Eq)]
pub(super) struct 升目をつなぐ木 {
    順に張った升目: Vec<木に張った升目>,
    張った座標: BTreeSet<升目の座標>,
}

impl 升目をつなぐ木 {
    /// 根から張り、1つでも到達できない升目が残れば型付きエラーで拒む。
    pub(super) fn 根から張る(表: &升目の表, 根: 升目の座標) -> Result<Self, ベイ格子エラー> {
        if !表.升目があるか(根) {
            return Err(ベイ格子エラー::根に指した升目が格子に無い { 座標: 根 });
        }
        let mut 木 = Self::根だけで始める(根);
        木.張った升目の隣を順に足す(表);
        木.到達しなかった升目を拒む(表)?;
        Ok(木)
    }

    /// 張った順の並び。根が先頭であり、以降は根に近い升目から並ぶ。
    pub(super) fn 順に数え上げる(&self) -> &[木に張った升目] {
        &self.順に張った升目
    }

    fn 根だけで始める(根: 升目の座標) -> Self {
        Self {
            順に張った升目: vec![木に張った升目::根として張る(根)],
            張った座標: BTreeSet::from([根]),
        }
    }

    /// 張った並びを先頭から走査し、まだ張っていない隣を継ぎ方の順に1つずつ足す。
    /// 走査の途中で並びが伸びるため、添字で追い、伸びが止まったところで終わる。
    fn 張った升目の隣を順に足す(&mut self, 表: &升目の表) {
        let mut 走査位置 = 0;
        while let Some(親の座標) = self.順に張った升目.get(走査位置).map(木に張った升目::座標) {
            for 継ぎ方 in 親からの継ぎ方::全ての継ぎ方を数え上げる() {
                self.隣を1つ足す(表, 親の座標, 継ぎ方);
            }
            走査位置 += 1;
        }
    }

    /// 名指した継ぎ方の先に升目があり、まだ張っていなければ1件足す。それ以外では何もしない。
    fn 隣を1つ足す(&mut self, 表: &升目の表, 親の座標: 升目の座標, 継ぎ方: 親からの継ぎ方) {
        let Some(子の座標) = 継ぎ方.子の座標(親の座標) else {
            return;
        };
        if !表.升目があるか(子の座標) || !self.張った座標.insert(子の座標) {
            return;
        }
        self.順に張った升目.push(木に張った升目::親から継いで張る(子の座標, 親の座標, 継ぎ方));
    }

    fn 到達しなかった升目を拒む(&self, 表: &升目の表) -> Result<(), ベイ格子エラー> {
        for 座標 in 表.座標を昇順に数え上げる() {
            if !self.張った座標.contains(&座標) {
                return Err(ベイ格子エラー::根から到達できない升目がある { 座標 });
            }
        }
        Ok(())
    }
}
