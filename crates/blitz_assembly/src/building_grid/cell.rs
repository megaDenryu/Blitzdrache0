//! 升目の宣言: 1つの升目に据わる骨格が何を受けるかを、4つの側面と2つの水平な面についてまとめた値。
//!
//! 骨格そのものを宣言に持たないのは、升目が在ることが骨格1件が据わることだからである。骨格を置くかどうかを
//! 別に持つと、升目が在るのに骨格が無いという状態が表せてしまう。
//!
//! 初期の宣言を「骨格だけを置く」にしてあるのは、人が升目を置いた直後の姿がそれだからである。
//! 面を1つずつ定める形にするのは、4つの側面を引数で並べる口が、正面と背面を取り違えても型を通すためである。

use super::cell_horizontal_face::{升目の屋根, 升目の床};
use super::opening_fill::はめ口の値;
use super::side_face::升目の側面;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 升目の宣言 {
    側面ごとのはめ口の値: [はめ口の値; 4],
    床: 升目の床,
    屋根: 升目の屋根,
}

impl 升目の宣言 {
    /// 骨格1件だけが据わり、壁も床も屋根も持たない宣言。
    pub fn 骨格だけを置く() -> Self {
        Self {
            側面ごとのはめ口の値: [はめ口の値::入れない; 4],
            床: 升目の床::張らない,
            屋根: 升目の屋根::載せない,
        }
    }

    pub fn 側面を定める(mut self, 側面: 升目の側面, 値: はめ口の値) -> Self {
        if let Some(枠) = self.側面ごとのはめ口の値.get_mut(側面.添字()) {
            *枠 = 値;
        }
        self
    }

    pub fn 床を定める(mut self, 床: 升目の床) -> Self {
        self.床 = 床;
        self
    }

    pub fn 屋根を定める(mut self, 屋根: 升目の屋根) -> Self {
        self.屋根 = 屋根;
        self
    }

    pub(super) fn 側面の値(&self, 側面: 升目の側面) -> はめ口の値 {
        match self.側面ごとのはめ口の値.get(側面.添字()) {
            Some(値) => *値,
            None => panic!("側面の添字が宣言の並びの長さを超えた。側面の数え上げと並びの長さが食い違っている"),
        }
    }

    pub(super) fn 床(&self) -> 升目の床 {
        self.床
    }

    pub(super) fn 屋根(&self) -> 升目の屋根 {
        self.屋根
    }
}
