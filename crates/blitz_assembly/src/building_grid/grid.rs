//! ベイ格子: 建物エディターが編集する升目の複体のうち、検査を通り木を張り終えた完成した形。
//!
//! 升目の間隔も階高も持たないのは、どこへ据わるかを接合点の宣言だけが決めるためである。人が画面で見る
//! 縮尺はエディターの責務であり、格子が持つと同じ建物が道具ごとに違う大きさで建つ。
//!
//! 生成の口を持たず組み手を通してのみ作れるのは、到達できない升目が無いことを升目1件ずつでは判定できない
//! ためである。半端な状態を完成した型へ漏らさない口を組み手へ1つだけ置く。
//! 参照: `_doc/計画/エディターからゲームまでの統合の作戦.md`

use crate::expansion::組み立て手順;

use super::cell_coordinate::升目の座標;
use super::cell_table::升目の表;
use super::part_spelling::骨格方式の部品の綴り;
use super::recipe_conversion::組み立て手順への写し取り;
use super::spanning_tree::升目をつなぐ木;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ベイ格子 {
    升目の表: 升目の表,
    根の升目: 升目の座標,
    つなぐ木: 升目をつなぐ木,
}

impl ベイ格子 {
    /// 組み手が宣言の破れと到達の破れを確かめてから呼ぶ口。
    pub(super) fn 検査を終えた材料から生成する(
        升目の表: 升目の表, 根の升目: 升目の座標, つなぐ木: 升目をつなぐ木
    ) -> Self {
        Self {
            升目の表,
            根の升目,
            つなぐ木,
        }
    }

    pub fn 升目の数(&self) -> usize {
        self.升目の表.件数()
    }

    pub fn 根の升目(&self) -> 升目の座標 {
        self.根の升目
    }

    /// 名指した綴りの部品で、この格子の組み立て手順を作る。接合点の宣言を1つも読まない純粋計算であり、
    /// 同じ格子と同じ綴りからは常に同じ手順が出る。
    pub fn 組み立て手順へ写す(&self, 部品の綴り: &骨格方式の部品の綴り) -> 組み立て手順 {
        組み立て手順への写し取り::格子と綴りから写し取る(self, 部品の綴り)
    }

    pub(super) fn 升目の表(&self) -> &升目の表 {
        &self.升目の表
    }

    pub(super) fn つなぐ木(&self) -> &升目をつなぐ木 {
        &self.つなぐ木
    }
}
