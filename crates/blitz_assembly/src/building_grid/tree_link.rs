//! 親からの継ぎ方: 木の1本の辺が、親の升目のどの口と子の升目のどの口を向かい合わせるか。
//!
//! 横へ継ぐ辺と上下へ積む辺を1つの型で数え上げるのは、渡す接合点の名前が違うだけで、接合の計算も指示の形も
//! 同じだからである。継ぎ方を選べば親と子の綴りが両方決まるため、親の右面を子の右面へ繋ぐ取り違えが書けない。
//!
//! 子の座標の導出をここが持つのは、継ぎ方と座標の進みが同じ1つの決定だからである。2箇所に分けると、
//! 木を張る走査と指示を組む工程で継ぎ方の意味が食い違い、宙に浮いた骨格が据わる。
//! `真下へ継ぐ`の向きは、根が最も下の階に無いときに要る。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格の上下積層とベイの継ぎ口(2026-08-19 追加)」

use crate::joint::接合点名;

use super::cell_coordinate::升目の座標;
use super::joint_spelling::{骨格の上面の接合点名, 骨格の下面の接合点名};
use super::side_face::升目の側面;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 親からの継ぎ方 {
    横の隣へ継ぐ { 親の側面: 升目の側面 }, // 同じ階で親の側面の継ぎ口へ子の向かい合う側面の継ぎ口を繋ぐ
    真上へ積む, // 親の骨格の上面へ子の骨格の下面を積む
    真下へ継ぐ, // 親の骨格の下面へ子の骨格の上面を繋ぐ
}

/// 木を張る走査が隣を見る順序。順序が変われば木の形が変わり、同じ格子から違う手順が出る。
const 全ての継ぎ方: [親からの継ぎ方; 6] = [
    親からの継ぎ方::横の隣へ継ぐ {
        親の側面: 升目の側面::正面
    },
    親からの継ぎ方::横の隣へ継ぐ {
        親の側面: 升目の側面::背面
    },
    親からの継ぎ方::横の隣へ継ぐ {
        親の側面: 升目の側面::左面
    },
    親からの継ぎ方::横の隣へ継ぐ {
        親の側面: 升目の側面::右面
    },
    親からの継ぎ方::真上へ積む,
    親からの継ぎ方::真下へ継ぐ,
];

impl 親からの継ぎ方 {
    pub(super) fn 全ての継ぎ方を数え上げる() -> [Self; 6] {
        全ての継ぎ方
    }

    /// この継ぎ方で親から辿り着く升目の座標。整数の端で溢れるときは辿り着く先が無いものとして答える。
    pub(super) fn 子の座標(self, 親の座標: 升目の座標) -> Option<升目の座標> {
        match self {
            Self::横の隣へ継ぐ { 親の側面 } => 親の座標.同じ階の隣(親の側面),
            Self::真上へ積む => 親の座標.真上の升目(),
            Self::真下へ継ぐ => 親の座標.真下の升目(),
        }
    }

    pub(super) fn 親の接合点名(self) -> 接合点名 {
        match self {
            Self::横の隣へ継ぐ { 親の側面 } => 親の側面.ベイの継ぎ口の接合点名(),
            Self::真上へ積む => 骨格の上面の接合点名(),
            Self::真下へ継ぐ => 骨格の下面の接合点名(),
        }
    }

    pub(super) fn 子の接合点名(self) -> 接合点名 {
        match self {
            Self::横の隣へ継ぐ { 親の側面 } => 親の側面.向かい合う側面().ベイの継ぎ口の接合点名(),
            Self::真上へ積む => 骨格の下面の接合点名(),
            Self::真下へ継ぐ => 骨格の上面の接合点名(),
        }
    }
}
