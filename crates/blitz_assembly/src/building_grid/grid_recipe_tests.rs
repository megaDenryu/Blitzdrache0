//! 格子の形が組み立て手順の姿に現れることの試験。担当するのは、道具が作る最小の格子が変換を通ることと、
//! 同じ格子から常に同じ手順が出ることと、根の既定と、隣を継ぐ面が継ぎの指示になることである。
//!
//! 飾りが指示になることの試験は`ornament_recipe_tests`が、既存の規則から作った配置表との突き合わせは
//! `crates/blitz_assembly/src/expansion/frame_tests.rs`の側が持つ。展開に要るカタログがそちらにあるためである。

#![allow(clippy::unwrap_used)]

use super::cell_coordinate::升目の座標;
use super::grid_fixture::{
    升目の並びから格子を組む, 右面を空けた升目, 四面へ平壁を入れた升目, 左面を空けた升目, 指示の姿一覧, 試験の部品の綴り
};

/// 道具が升目を1つ置いて4面へ壁を入れた最小の格子は、必ず変換を通って壁4枚ぶんの指示になる。
#[test]
fn 最小の初期格子が組み立て手順へ写る() {
    let 格子 = 升目の並びから格子を組む(&[(升目の座標::生成する(0, 0, 0), 四面へ平壁を入れた升目())]);
    let 手順 = 格子.組み立て手順へ写す(&試験の部品の綴り());
    assert_eq!(手順.根の部品().綴り(), "一間四方の骨格");
    assert_eq!(手順.指示一覧().len(), 4, "1升目に壁4枚を入れた格子の指示の件数");
}

#[test]
fn 同じ格子と同じ綴りからは同じ手順が出る() {
    let 格子 = 升目の並びから格子を組む(&[
        (升目の座標::生成する(0, 0, 0), 右面を空けた升目()),
        (升目の座標::生成する(1, 0, 0), 左面を空けた升目()),
    ]);
    let 綴り = 試験の部品の綴り();
    assert_eq!(
        指示の姿一覧(&格子.組み立て手順へ写す(&綴り)),
        指示の姿一覧(&格子.組み立て手順へ写す(&綴り))
    );
}

/// 根を人が選ばなければ最初に置いた升目が根になる。座標の最も小さい升目ではない。
#[test]
fn 根の既定は最初に置いた升目である() {
    let 後から置いた座標 = 升目の座標::生成する(-1, 0, 0);
    let 格子 = 升目の並びから格子を組む(&[
        (升目の座標::生成する(0, 0, 0), 左面を空けた升目()),
        (後から置いた座標, 右面を空けた升目()),
    ]);
    assert_eq!(格子.根の升目(), 升目の座標::生成する(0, 0, 0));
    assert_ne!(格子.根の升目(), 後から置いた座標);
}

/// 隣を継ぐ面には壁が入らず、代わりに骨格を継ぐ指示が1件出る。壁3枚が2升目ぶんで6件、継ぎが1件である。
#[test]
fn 横に継いだ格子は継ぎの指示を1件だけ持つ() {
    let 格子 = 升目の並びから格子を組む(&[
        (升目の座標::生成する(0, 0, 0), 右面を空けた升目()),
        (升目の座標::生成する(1, 0, 0), 左面を空けた升目()),
    ]);
    let 姿一覧 = 指示の姿一覧(&格子.組み立て手順へ写す(&試験の部品の綴り()));
    assert_eq!(姿一覧.len(), 7);
    assert_eq!(姿一覧.get(3).map(String::as_str), Some("0の右面の継ぎ口へ一間四方の骨格の左面の継ぎ口"));
}
