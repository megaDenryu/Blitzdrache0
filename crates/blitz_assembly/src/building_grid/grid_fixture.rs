//! ベイ格子の試験の材料。部品の綴りと、よく使う升目の宣言と、升目の並びから格子を組む口を持つ。
//!
//! 綴りを実データの名前でなく骨格方式の試験のカタログが使う名前に合わせているのは、格子から作った手順を
//! その既存のカタログでそのまま展開し、規則から作った配置表と突き合わせるためである。
//! 実データの綴りの正本は`crates/blitz_asset_compiler/examples/part_assembly/frame_bay_spelling.rs`にある。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use crate::expansion::組み立て手順;
use crate::part::部品ID;

use super::cell::升目の宣言;
use super::cell_coordinate::升目の座標;
use super::grid::ベイ格子;
use super::grid_builder::ベイ格子の組み手;
use super::opening_fill::{はめ口の値, 壁の種類};
use super::ornament::壁の外面へ付ける飾り;
use super::part_role::骨格方式の部品の役割;
use super::part_spelling::骨格方式の部品の綴り;
use super::part_spelling_builder::骨格方式の部品の綴りの組み手;
use super::side_face::升目の側面;

const 役割ごとの綴り: [(骨格方式の部品の役割, &str); 8] = [
    (骨格方式の部品の役割::骨格, "一間四方の骨格"),
    (骨格方式の部品の役割::平壁, "平壁"),
    (骨格方式の部品の役割::窓壁, "窓壁"),
    (骨格方式の部品の役割::扉枠付きの壁, "扉枠付きの壁"),
    (骨格方式の部品の役割::切妻屋根, "切妻屋根"),
    (骨格方式の部品の役割::床板, "床板"),
    (骨格方式の部品の役割::出窓, "出窓"),
    (骨格方式の部品の役割::煙突セグメント, "煙突"),
];

pub(crate) fn 試験の部品の綴り() -> 骨格方式の部品の綴り {
    let mut 組み手 = 骨格方式の部品の綴りの組み手::空から始める();
    for (役割, 綴り) in 役割ごとの綴り {
        組み手.部品を1つ定める(役割, 部品ID::生成する(綴り).unwrap());
    }
    組み手.綴りを閉じる().unwrap()
}

/// 外面に飾りを付けない壁のはめ口の値。
pub(crate) fn 飾りを付けない壁(種類: 壁の種類) -> はめ口の値 {
    はめ口の値::壁を入れる {
        種類,
        外面の飾り: 壁の外面へ付ける飾り::付けない,
    }
}

/// 4つの側面すべてへ平壁を入れた升目。
pub(crate) fn 四面へ平壁を入れた升目() -> 升目の宣言 {
    名指した側面だけを空けて平壁を入れた升目(None)
}

/// 右面だけを空けて残る3面へ平壁を入れた升目。右隣のベイへ継ぐ升目がこれである。
pub(crate) fn 右面を空けた升目() -> 升目の宣言 {
    名指した側面だけを空けて平壁を入れた升目(Some(升目の側面::右面))
}

/// 左面だけを空けて残る3面へ平壁を入れた升目。左隣のベイから継がれる升目がこれである。
pub(crate) fn 左面を空けた升目() -> 升目の宣言 {
    名指した側面だけを空けて平壁を入れた升目(Some(升目の側面::左面))
}

/// 名指した側面だけを空け、残りの側面へ平壁を入れた升目。隣を継ぐ面へ壁を入れない形をこれで作る。
fn 名指した側面だけを空けて平壁を入れた升目(空ける側面: Option<升目の側面>) -> 升目の宣言 {
    升目の側面::全側面を数え上げる()
        .into_iter()
        .filter(|側面| Some(*側面) != 空ける側面)
        .fold(升目の宣言::骨格だけを置く(), |宣言, 側面| {
            宣言.側面を定める(側面, 飾りを付けない壁(壁の種類::平壁))
        })
}

/// 升目の並びを順に置き、最初に置いた升目を根にして閉じた格子。検査に落ちる並びを渡してはならない。
pub(crate) fn 升目の並びから格子を組む(升目の並び: &[(升目の座標, 升目の宣言)]) -> ベイ格子 {
    let mut 組み手 = ベイ格子の組み手::空から始める();
    for (座標, 宣言) in 升目の並び {
        組み手.升目を1つ置く(*座標, *宣言).unwrap();
    }
    組み手.最初に置いた升目を根にして閉じる().unwrap()
}

/// 手順の指示1件ずつの姿を1行の綴りにする。親の番号と2つの接合点と子の部品が同じなら、同じ組み方を表す。
/// 姿の並びで確かめるのは、指示の件数だけでは繋ぎ先の取り違えが見えないためである。
pub(crate) fn 指示の姿一覧(手順: &組み立て手順) -> Vec<String> {
    手順
        .指示一覧()
        .iter()
        .map(|指示| format!("{}の{}へ{}の{}", 指示.親.番号を返す(), 指示.親の接合点, 指示.子の部品, 指示.子の接合点))
        .collect()
}
