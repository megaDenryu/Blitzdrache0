//! 組み立て手順への写し取り: ベイ格子の木を根から順に辿り、升目1つを骨格・床・壁・飾り・屋根の指示へ写す型。
//!
//! 升目ごとに骨格を据えた番号を覚えるのは、子の升目が親の骨格を番号で指すためである。木が幅優先で並んで
//! いるため親は必ず先に据わっており、覚えていない番号を引くことは起こりえない。
//!
//! 積む順を「骨格・床・4つの側面・屋根」に固定するのは、同じ格子から常に同じ手順が出ることを守るためであり、
//! 骨格を連ねる既存の規則が積む順と揃えるためでもある。順が揃っていることで、同じ形の建物を格子から作っても
//! 規則から作っても、据えた順の並びまで同じ配置表になる。

use std::collections::BTreeMap;

use crate::expansion::{指示の並びの組み手, 据えた部品の番号, 接合の指示, 組み立て手順};
use crate::joint::{接合面上の位置, 法線方向のずらし};

use super::cell_coordinate::升目の座標;
use super::grid::ベイ格子;
use super::part_role::骨格方式の部品の役割;
use super::part_spelling::骨格方式の部品の綴り;
use super::side_face::升目の側面;
use super::tree_node::木に張った升目;
use super::wall_step::据わった骨格へ壁と飾りを積む係;

pub(super) struct 組み立て手順への写し取り<'材料> {
    格子: &'材料 ベイ格子,
    綴り: &'材料 骨格方式の部品の綴り,
    並びの組み手: 指示の並びの組み手,
    升目ごとの骨格の番号: BTreeMap<升目の座標, 据えた部品の番号>,
}

impl<'材料> 組み立て手順への写し取り<'材料> {
    pub(super) fn 格子と綴りから写し取る(
        格子: &'材料 ベイ格子, 綴り: &'材料 骨格方式の部品の綴り
    ) -> 組み立て手順 {
        let mut 写し取り = Self {
            格子,
            綴り,
            並びの組み手: 指示の並びの組み手::空から始める(),
            升目ごとの骨格の番号: BTreeMap::new(),
        };
        for 升目 in 格子.つなぐ木().順に数え上げる() {
            写し取り.升目を1つ組む(升目);
        }
        let 根の部品 = 綴り.役割から部品の識別子を引く(骨格方式の部品の役割::骨格).clone();
        組み立て手順::根と指示から生成する(根の部品, 写し取り.並びの組み手.指示一覧へ畳む())
    }

    fn 升目を1つ組む(&mut self, 升目: &木に張った升目) {
        let 骨格の番号 = self.骨格を据える(升目);
        self.升目ごとの骨格の番号.insert(升目.座標(), 骨格の番号);
        let Some(宣言) = self.格子.升目の表().宣言を引く(升目.座標()) else {
            return;
        };
        if let Some(床の指示) = 宣言.床().床板を張る指示(self.綴り, 骨格の番号) {
            self.並びの組み手.接合を1つ積む(床の指示);
        }
        let 仕上げ係 = 据わった骨格へ壁と飾りを積む係::骨格の番号と綴りから始める(self.綴り, 骨格の番号);
        for 側面 in 升目の側面::全側面を数え上げる() {
            仕上げ係.側面を1つ仕上げる(&mut self.並びの組み手, 側面, 宣言.側面の値(側面));
        }
        if let Some(屋根の指示) = 宣言.屋根().屋根を載せる指示(self.綴り, 骨格の番号) {
            self.並びの組み手.接合を1つ積む(屋根の指示);
        }
    }

    /// 根の升目の骨格は手順の根そのものであり、指示を1件も積まない。それ以外の升目は親の骨格へ継ぐ。
    /// 積層も継ぎも面が向かい合う隣接であるため、法線方向へは寄せない。
    fn 骨格を据える(&mut self, 升目: &木に張った升目) -> 据えた部品の番号 {
        let Some(繋がり) = 升目.親への繋がり() else {
            return 据えた部品の番号::根();
        };
        let Some(親の番号) = self.升目ごとの骨格の番号.get(&繋がり.親の座標()).copied() else {
            panic!("親の升目がまだ据わっていない。木が幅優先に並んでいるという不変条件に違反した");
        };
        self.並びの組み手.接合を1つ積む(接合の指示 {
            親: 親の番号,
            親の接合点: 繋がり.継ぎ方().親の接合点名(),
            子の部品: self.綴り.役割から部品の識別子を引く(骨格方式の部品の役割::骨格).clone(),
            子の接合点: 繋がり.継ぎ方().子の接合点名(),
            面上の位置: 接合面上の位置::中心(),
            法線方向のずらし: 法線方向のずらし::寄せない(),
        })
    }
}
