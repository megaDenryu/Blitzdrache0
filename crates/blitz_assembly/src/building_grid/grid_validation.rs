//! 升目の宣言そのものが成り立つかの検査。担当するのは、階の下が抜けていないことと、隣を継ぐ面へ壁が
//! 入っていないことと、真上に升目がある升目が屋根を載せていないことである。
//!
//! 根から到達できるかの検査(`spanning_tree`)から分けるのは、要る材料が違うためである。こちらは升目1つと
//! その近さだけを見て決まり、あちらは格子ぜんたいを走査して初めて決まる。
//!
//! 隣を継ぐ面へ壁を拒むのは、同じ物理面が「壁を受ける口」と「隣を継ぐ口」の2つの意味を持ち、どちらか一方
//! だけを使うためである。両方を使うと、隣のベイの中へ壁が1枚立つ。内壁を表す部品はまだ実物になっていない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「ベイの継ぎ口の裁定(2026-08-19、札#145のコメント368)」

use super::cell::升目の宣言;
use super::cell_coordinate::升目の座標;
use super::cell_table::升目の表;
use super::error::ベイ格子エラー;
use super::side_face::升目の側面;

/// 表のすべての升目の宣言を昇順に見て、最初に見つけた破れを返す。
pub(super) fn 宣言の破れを拒む(表: &升目の表) -> Result<(), ベイ格子エラー> {
    for 座標 in 表.座標を昇順に数え上げる() {
        let Some(宣言) = 表.宣言を引く(座標) else {
            continue;
        };
        真下の升目を課す(表, 座標)?;
        隣を継ぐ面の壁を拒む(表, 座標, 宣言)?;
        最上階でない升目の屋根を拒む(表, 座標, 宣言)?;
    }
    Ok(())
}

/// 最も下の階より上の升目には、同じ横と奥の真下の升目を課す。宙に浮いた階を組めなくするためである。
fn 真下の升目を課す(表: &升目の表, 座標: 升目の座標) -> Result<(), ベイ格子エラー> {
    if 座標.階() > 0 && !表.真下に升目があるか(座標) {
        return Err(ベイ格子エラー::真下に升目が無い { 座標 });
    }
    Ok(())
}

fn 隣を継ぐ面の壁を拒む(表: &升目の表, 座標: 升目の座標, 宣言: 升目の宣言) -> Result<(), ベイ格子エラー> {
    for 側面 in 升目の側面::全側面を数え上げる() {
        if 表.同じ階の隣に升目があるか(座標, 側面) && 宣言.側面の値(側面).壁を入れるか() {
            return Err(ベイ格子エラー::隣の升目がある側面へ壁を入れている { 座標, 側面 });
        }
    }
    Ok(())
}

/// 屋根が載るのは真上に升目の無い升目だけである。骨格の上面は上の階を積む口と同じ面であり、
/// 両方を使うと上の階の中へ屋根が1つ入る。
fn 最上階でない升目の屋根を拒む(
    表: &升目の表, 座標: 升目の座標, 宣言: 升目の宣言
) -> Result<(), ベイ格子エラー> {
    if 表.真上に升目があるか(座標) && 宣言.屋根().載せるか() {
        return Err(ベイ格子エラー::真上に升目がある升目へ屋根を載せている { 座標 });
    }
    Ok(())
}
