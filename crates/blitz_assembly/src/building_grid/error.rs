//! ベイ格子が成り立たない事情。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! 文面へ座標と側面を載せるのは、読み手が升目のどれを直すかを決めるためである。件数だけを返すと、
//! 建物の升目が数十ある編集で直す先が分からない。

use thiserror::Error;

use super::cell_coordinate::升目の座標;
use super::part_role::骨格方式の部品の役割;
use super::side_face::升目の側面;

#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum ベイ格子エラー {
    #[error("升目が1つも無い。骨格を1件も持たない建物は組み立てられない")]
    升目が1つも無い,

    #[error("座標({座標})へ升目を二重に置いた。1つの座標に据わる骨格は1件である")]
    同じ座標へ升目を二重に置いた { 座標: 升目の座標 },

    #[error("根に指した升目({座標})が格子に無い。根は格子の升目のどれか1つである")]
    根に指した升目が格子に無い { 座標: 升目の座標 },

    #[error("升目({座標})の真下に升目が無い。階を積むには真下の同じ横と奥の升目が要る")]
    真下に升目が無い { 座標: 升目の座標 },

    #[error("升目({座標})の{側面}には隣の升目があるのに壁を入れている。隣を継ぐ面と壁を入れる面は排他である")]
    隣の升目がある側面へ壁を入れている { 座標: 升目の座標, 側面: 升目の側面 },

    #[error("升目({座標})の真上に升目があるのに屋根を載せている。屋根が載るのは最上階の升目だけである")]
    真上に升目がある升目へ屋根を載せている { 座標: 升目の座標 },

    #[error("升目({座標})へ根から到達できない。すべての升目が隣接か上下で根と繋がっていることが要る")]
    根から到達できない升目がある { 座標: 升目の座標 },

    #[error("煙突の段数が零である。壁の外面へ立てる以上、1段目は必ずあるため下限は1である")]
    煙突の段数が零である,

    #[error("部品の綴りのうち{役割}が定まっていない。8つの役割すべてに綴りを預けることが要る")]
    部品の綴りが定まっていない { 役割: 骨格方式の部品の役割 },
}
