//! 升目の側面の壁の外面へ何を付けるかの宣言と、煙突が何段積むかの値。
//!
//! 飾りを壁の宣言の中へ入れ子にするのは、壁の無い面へ飾りだけが浮く宣言を型で書けなくするためである。
//! 展開の層の`壁の外面の飾り`と分けるのは、あちらが候補の並びから種で引く形であり、こちらが人の編集の
//! 結果として1つに定まった宣言だからである。**格子は候補を並べず、選んだものだけを持つ。**
//!
//! 煙突の段数を裸の数で持たないのは、零段の煙突が「壁の外面へ立てるのに1段も無い」という半端な状態に
//! なるためである。生成の時点で拒み、後の工程が段数を確かめずに済むようにする。
//! **`出窓を差し込む`の出窓は葉であり、上へ積み足すものを1件も持たない。**
//! 参照: `_doc/設計/部品カタログと接合点.md`「煙突を骨格の家へ立てる(2026-08-20、Blitzdrache0Assetsのd319187)」

use crate::joint::{接合面上の位置, 法線方向のずらし};

use super::error::ベイ格子エラー;
use super::joint_spelling::{壁の外面の飾り取付の接合点名, 接合点名を作る};
use super::part_role::骨格方式の部品の役割;
use super::part_spelling::骨格方式の部品の綴り;
use crate::expansion::{据えた部品の番号, 接合の指示};

/// 壁の外面へ立てる煙突の段数。1段目が壁の外面へ差し込まれ、2段目からは1つ下の段の上面へ積む。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 煙突の段数(usize);

impl 煙突の段数 {
    pub fn 生成する(段数: usize) -> Result<Self, ベイ格子エラー> {
        if 段数 == 0 {
            return Err(ベイ格子エラー::煙突の段数が零である);
        }
        Ok(Self(段数))
    }

    /// 1段目の上へ積み足す段の数。1段だけの煙突では零である。
    pub(super) fn 上へ積み足す段数(self) -> usize {
        self.0.saturating_sub(1)
    }

    pub fn 段数を返す(self) -> usize {
        self.0
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 壁の外面へ付ける飾り {
    付けない,
    出窓を差し込む, // 一体型の家から流用する出窓
    煙突を立てる {
        段数: 煙突の段数,
    },
}

impl 壁の外面へ付ける飾り {
    /// 名指した壁の外面へこの飾りを差し込む指示。付けない宣言では指示が1件も出ない。
    /// 寄せないのは、差し込む面と取付面が零で密着するというBlender側の申告に従うためである。
    pub(super) fn 壁の外面へ差し込む指示(
        self, 綴り: &骨格方式の部品の綴り, 据えた壁の番号: 据えた部品の番号
    ) -> Option<接合の指示> {
        let (役割, 差込口の綴り) = match self {
            Self::付けない => return None,
            Self::出窓を差し込む => (骨格方式の部品の役割::出窓, "壁面差込口"),
            Self::煙突を立てる { .. } => (骨格方式の部品の役割::煙突セグメント, "壁面密着面"),
        };
        Some(接合の指示 {
            親: 据えた壁の番号,
            親の接合点: 壁の外面の飾り取付の接合点名(),
            子の部品: 綴り.役割から部品の識別子を引く(役割).clone(),
            子の接合点: 接合点名を作る(差込口の綴り),
            面上の位置: 接合面上の位置::中心(),
            法線方向のずらし: 法線方向のずらし::寄せない(),
        })
    }

    pub(super) fn 上へ積み足す段数(self) -> usize {
        match self {
            Self::付けない | Self::出窓を差し込む => 0,
            Self::煙突を立てる { 段数 } => 段数.上へ積み足す段数(),
        }
    }

    /// 直前に据えた段の上面へ次の段を積む指示。段を積まない飾りでは指示が1件も出ない。
    pub(super) fn 上へ1段積み足す指示(
        self, 綴り: &骨格方式の部品の綴り, 直前に据えた部品: 据えた部品の番号
    ) -> Option<接合の指示> {
        match self {
            Self::付けない | Self::出窓を差し込む => None,
            Self::煙突を立てる { .. } => Some(接合の指示 {
                親: 直前に据えた部品,
                親の接合点: 接合点名を作る("上面"),
                子の部品: 綴り.役割から部品の識別子を引く(骨格方式の部品の役割::煙突セグメント).clone(),
                子の接合点: 接合点名を作る("下面"),
                面上の位置: 接合面上の位置::中心(),
                法線方向のずらし: 法線方向のずらし::寄せない(),
            }),
        }
    }
}
