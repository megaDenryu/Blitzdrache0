//! 据わった骨格へ壁と飾りを積む係: 骨格1件の番号を持ち、側面1つぶんの壁と、その壁の外面の飾りと、
//! 飾りの上へ積み足す段を順に積む。
//!
//! 手順の写し取り(`recipe_conversion`)から分けるのは、責務が違うためである。写し取りは木の並びを辿って
//! 升目ごとに骨格を据え、この係は据わった骨格1件の側面を仕上げることだけを受け持つ。
//!
//! 指示の並びの組み手を引数で受けて保持しないのは、指示の並びの所有者が写し取りだからである。
//! この係が写しを持つと、積んだ番号の数え方が2つに分かれる。
//!
//! **飾りの親は骨格でなく、いま据えたばかりの壁である。** 壁を積んだ結果として返る番号をそのまま飾りの親に
//! 使う。壁が入らなかった面では飾りを積まない。壁の無い面へ飾りだけが浮くことは起こりえない。

use crate::expansion::{指示の並びの組み手, 据えた部品の番号};

use super::opening_fill::はめ口の値;
use super::part_spelling::骨格方式の部品の綴り;
use super::side_face::升目の側面;

pub(super) struct 据わった骨格へ壁と飾りを積む係<'材料> {
    綴り: &'材料 骨格方式の部品の綴り,
    据わった骨格の番号: 据えた部品の番号,
}

impl<'材料> 据わった骨格へ壁と飾りを積む係<'材料> {
    pub(super) fn 骨格の番号と綴りから始める(
        綴り: &'材料 骨格方式の部品の綴り, 据わった骨格の番号: 据えた部品の番号
    ) -> Self {
        Self {
            綴り, 据わった骨格の番号
        }
    }

    /// 名指した側面へ壁を1枚まで入れ、入ったなら続けてその壁の外面へ飾りを積む。
    pub(super) fn 側面を1つ仕上げる(
        &self, 並びの組み手: &mut 指示の並びの組み手, 側面: 升目の側面, 値: はめ口の値
    ) {
        let はめ口 = 側面.壁のはめ口の接合点名();
        let Some(壁の指示) = 値.骨格へはめる指示(self.綴り, self.据わった骨格の番号, はめ口) else {
            return;
        };
        let 据えた壁の番号 = 並びの組み手.接合を1つ積む(壁の指示);
        self.壁の外面へ飾りを積む(並びの組み手, 値, 据えた壁の番号);
    }

    /// 壁の外面へ飾りを1つまで差し込み、その飾りの上へ宣言された段数だけ積み足す。
    /// 煙突の2段目以降がこれであり、骨格から壁へ、壁から飾りへ、飾りから次の段へと組み立てが3段以上に伸びる。
    fn 壁の外面へ飾りを積む(
        &self, 並びの組み手: &mut 指示の並びの組み手, 値: はめ口の値, 据えた壁の番号: 据えた部品の番号
    ) {
        let 飾り = 値.外面の飾り();
        let Some(飾りの指示) = 飾り.壁の外面へ差し込む指示(self.綴り, 据えた壁の番号) else {
            return;
        };
        let mut 直前に据えた部品 = 並びの組み手.接合を1つ積む(飾りの指示);
        for _ in 0..飾り.上へ積み足す段数() {
            let Some(積み足す指示) = 飾り.上へ1段積み足す指示(self.綴り, 直前に据えた部品) else {
                return;
            };
            直前に据えた部品 = 並びの組み手.接合を1つ積む(積み足す指示);
        }
    }
}
