//! 升目の側面のはめ口へ何を入れるかの宣言。壁を入れないか、3種のうち1種の壁を外面の飾りごと入れるかである。
//!
//! 展開の層の`はめ口へ入れるもの`と分けるのは、あちらが候補の並びから種で引く形であり、こちらが人の編集の
//! 結果として1つに定まった宣言だからである。後日この枝を候補の並びへ広げるときも、格子の側が
//! 「何を選んだか」でなく「何から引くか」を持つ形へ変わるだけであり、変換の側は動かない。
//!
//! 食い込ませる量0.02メートルは部品の寸法から導けない配置の決定である。零にすると骨格の柱と梁の外面と
//! 壁の背面がちょうど同一平面になり、深度が競合する。**この破れは接触の検査に掛からず絵にだけ出る。**
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格と壁の対、扉の対」

use blitz_math::メートル;

use crate::expansion::{据えた部品の番号, 接合の指示};
use crate::joint::{接合点名, 接合面上の位置, 法線方向のずらし};

use super::joint_spelling::壁の外枠の接合点名;
use super::ornament::壁の外面へ付ける飾り;
use super::part_role::骨格方式の部品の役割;
use super::part_spelling::骨格方式の部品の綴り;

const 骨格へ食い込ませる量: f32 = 0.02;

/// はめ口へ入れる壁の種類。壁3種の外枠は同じ位置と姿勢と寸法で宣言されているため接合には現れず、
/// 違うのはメッシュと材質スロットの数だけである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 壁の種類 {
    平壁,
    窓壁,
    扉枠付きの壁,
}

impl 壁の種類 {
    fn 役割(self) -> 骨格方式の部品の役割 {
        match self {
            Self::平壁 => 骨格方式の部品の役割::平壁,
            Self::窓壁 => 骨格方式の部品の役割::窓壁,
            Self::扉枠付きの壁 => 骨格方式の部品の役割::扉枠付きの壁,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum はめ口の値 {
    入れない,
    壁を入れる {
        種類: 壁の種類,
        外面の飾り: 壁の外面へ付ける飾り,
    },
}

impl はめ口の値 {
    pub(super) fn 壁を入れるか(self) -> bool {
        matches!(self, Self::壁を入れる { .. })
    }

    pub(super) fn 外面の飾り(self) -> 壁の外面へ付ける飾り {
        match self {
            Self::入れない => 壁の外面へ付ける飾り::付けない,
            Self::壁を入れる { 外面の飾り, .. } => 外面の飾り,
        }
    }

    /// 名指した骨格の名指したはめ口へこの宣言の壁をはめる指示。入れない宣言では指示が1件も出ない。
    /// **一致の様式であるため、面上の位置は中心のほかに置きようがない。**
    pub(super) fn 骨格へはめる指示(
        self, 綴り: &骨格方式の部品の綴り, 親: 据えた部品の番号, はめ口: 接合点名
    ) -> Option<接合の指示> {
        let Self::壁を入れる { 種類, .. } = self else {
            return None;
        };
        Some(接合の指示 {
            親,
            親の接合点: はめ口,
            子の部品: 綴り.役割から部品の識別子を引く(種類.役割()).clone(),
            子の接合点: 壁の外枠の接合点名(),
            面上の位置: 接合面上の位置::中心(),
            法線方向のずらし: 骨格の面へ食い込ませるずらし(),
        })
    }
}

/// 骨格の面へ壁を食い込ませるずらし。定数から作るため、非有限を拒む検査に掛かることはない。
fn 骨格の面へ食い込ませるずらし() -> 法線方向のずらし {
    match 法線方向のずらし::食い込ませる量から生成する(メートル::生成する(骨格へ食い込ませる量)) {
        Ok(ずらし) => ずらし,
        Err(_) => panic!("壁を食い込ませる量が有限でない。定数を書き換えたときにしか起こらない"),
    }
}
