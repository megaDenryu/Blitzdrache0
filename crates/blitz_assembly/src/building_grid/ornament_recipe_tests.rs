//! 壁の外面の飾りが組み立て手順の姿に現れることの試験。担当するのは、出窓が葉のまま1件だけ据わることと、
//! 煙突が宣言した段数だけ積み足されることである。格子の形が指示になることの試験は`grid_recipe_tests`が持つ。
//!
//! 飾りだけを別の試験にするのは、確かめる軸が違うためである。あちらは升目の繋がりが指示の形を決めることを見る。
//! こちらは1枚の壁の上へ組み立てが2段以上に伸びることを見る。

#![allow(clippy::unwrap_used)]

use super::cell_coordinate::升目の座標;
use super::grid_fixture::{升目の並びから格子を組む, 四面へ平壁を入れた升目, 指示の姿一覧, 試験の部品の綴り};
use super::opening_fill::{はめ口の値, 壁の種類};
use super::ornament::{壁の外面へ付ける飾り, 煙突の段数};
use super::side_face::升目の側面;

/// 背面の壁だけが名指した飾りを持ち、残る3面は平壁だけの升目から作った指示の姿の並び。
fn 背面へ飾りを付けた升目の指示の姿一覧(飾り: 壁の外面へ付ける飾り) -> Vec<String> {
    let 飾りつきの壁 = はめ口の値::壁を入れる {
        種類: 壁の種類::平壁,
        外面の飾り: 飾り,
    };
    let 升目 = 四面へ平壁を入れた升目().側面を定める(升目の側面::背面, 飾りつきの壁);
    let 格子 = 升目の並びから格子を組む(&[(升目の座標::生成する(0, 0, 0), 升目)]);
    指示の姿一覧(&格子.組み立て手順へ写す(&試験の部品の綴り()))
}

/// 出窓は葉であり、上へ積み足すものを1件も持たない。壁4枚と出窓1件で5件である。
#[test]
fn 出窓は壁の外面へ一件だけ据わる() {
    let 姿一覧 = 背面へ飾りを付けた升目の指示の姿一覧(壁の外面へ付ける飾り::出窓を差し込む);
    assert_eq!(姿一覧.len(), 5, "壁4枚と出窓1件の指示の件数");
    assert_eq!(姿一覧.get(2).map(String::as_str), Some("2の外面の飾り取付へ出窓の壁面差込口"));
}

/// 煙突は葉でなく、宣言した段数だけ指示が出る。2段の煙突は1段目を壁の外面へ差し込み、2段目を上面へ積む。
#[test]
fn 煙突の段数だけ飾りの指示が増える() {
    let 姿一覧 = 背面へ飾りを付けた升目の指示の姿一覧(壁の外面へ付ける飾り::煙突を立てる {
        段数: 煙突の段数::生成する(2).unwrap(),
    });
    assert_eq!(姿一覧.len(), 6, "壁4枚と煙突2段の指示の件数");
    assert_eq!(姿一覧.get(2).map(String::as_str), Some("2の外面の飾り取付へ煙突の壁面密着面"));
    assert_eq!(姿一覧.get(3).map(String::as_str), Some("3の上面へ煙突の下面"));
}

/// 1段だけの煙突は積み足す段を持たない。段数が指示の件数をそのまま決めていることの証拠である。
#[test]
fn 一段の煙突は積み足す段を持たない() {
    let 姿一覧 = 背面へ飾りを付けた升目の指示の姿一覧(壁の外面へ付ける飾り::煙突を立てる {
        段数: 煙突の段数::生成する(1).unwrap(),
    });
    assert_eq!(姿一覧.len(), 5, "壁4枚と煙突1段の指示の件数");
}
