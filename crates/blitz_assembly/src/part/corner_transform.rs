//! 境界箱の角を個体配置で写す工程。受け取るのは配置と部品ローカルの角、返すのは群ローカルの角である。
//!
//! 箱の定義から分けているのは、これが「配置の成分をどう効かせるか」という1つの工程であり、
//! 呼び出し元が四元数の展開を知らずに呼べるためである。
//!
//! 生の成分で書くのは、個体配置が回転を成分で持ち、ここが検証のためだけの計算であって、
//! ドメインの語彙を通す必要が無いためである。

use blitz_engine::個体配置;

/// 配置の倍率・回転・平行移動をこの順で角へ効かせる。個体配置の変換の定義と同じ順である。
pub(super) fn 配置で角を写す(配置: &個体配置, 角: [f32; 3]) -> [f32; 3] {
    let 倍率 = 配置.スケール();
    let 回転 = 配置.回転();
    let 伸ばした = [角[0] * 倍率[0], 角[1] * 倍率[1], 角[2] * 倍率[2]];
    let 回した = クォータニオンで回す(回転, 伸ばした);
    let 平行移動 = 配置.平行移動();
    [回した[0] + 平行移動[0], 回した[1] + 平行移動[1], 回した[2] + 平行移動[2]]
}

/// クォータニオンでベクトルを回す。生の成分で書くのは、個体配置が回転を成分で持ち、
/// ここが検証のためだけの計算であって、ドメインの語彙を通す必要が無いためである。
fn クォータニオンで回す(回転: [f32; 4], ベクトル: [f32; 3]) -> [f32; 3] {
    let [x, y, z, w] = 回転;
    let 外積1 = [
        y * ベクトル[2] - z * ベクトル[1] + w * ベクトル[0],
        z * ベクトル[0] - x * ベクトル[2] + w * ベクトル[1],
        x * ベクトル[1] - y * ベクトル[0] + w * ベクトル[2],
    ];
    [
        ベクトル[0] + 2.0 * (y * 外積1[2] - z * 外積1[1]),
        ベクトル[1] + 2.0 * (z * 外積1[0] - x * 外積1[2]),
        ベクトル[2] + 2.0 * (x * 外積1[1] - y * 外積1[0]),
    ]
}
