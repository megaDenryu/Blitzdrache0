//! 部品の境界箱: 1つの部品が占める、部品のローカル座標系での軸平行な直方体。
//!
//! 部品定義が持たないのは、配置の計算に要らないためである。接合点だけで配置は決まる。この箱が要るのは2つの側である。
//! 1つは検証であり、組み上げた部品が親と接しているか(宙に浮いていないか)を見る。もう1つは建物の静的物理形状であり、
//! 据えた部品1件がそのまま子形状の直方体になる(参照: `_doc/設計/世界の形と衝突基盤.md`「判断5: 形状の目録を先に確定する(物理形状と描画形状は別物)」)。
//!
//! 写した箱に2つの形があるのはこの2つの用途に対応する。検証が使う軸平行の箱は8つの角を写してから外接を取るため、
//! 回転が入ると実際より大きい箱になる。**大きい側へ外れる誤差は、接触の判定を甘くする側へしか働かない。**
//! 接していないものを接していると誤って通すことはあるが、接しているものを落とすことはない。
//! 物理形状が使う任意姿勢の直方体は近似を持たず、部品ローカルで軸平行という性質をそのまま運ぶ。

use blitz_engine::static_shape::{任意姿勢の直方体, 直方体の軸ごとの半分の長さ, 静的物理形状エラー};
use blitz_engine::個体配置;
use blitz_math::{クォータニオン, メートル, 位置};

use super::corner_transform::配置で角を写す;
use super::error::カタログエラー;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 部品の境界箱 {
    最小: [f32; 3],
    最大: [f32; 3],
}

impl 部品の境界箱 {
    /// 最小が最大を超える箱を型付きエラーで拒む。向きの壊れた箱は接触の判定を無意味にする。
    pub fn 最小と最大から生成する(最小: [f32; 3], 最大: [f32; 3]) -> Result<Self, カタログエラー> {
        for 軸 in 0..3 {
            if !最小[軸].is_finite() || !最大[軸].is_finite() || 最小[軸] > 最大[軸] {
                return Err(カタログエラー::境界箱の最小が最大を超える { 軸 });
            }
        }
        Ok(Self { 最小, 最大 })
    }

    /// 配置で写した8つの角へ外接する、群のローカル座標系での軸平行な箱。
    pub fn 配置で写す(&self, 配置: &個体配置) -> 群ローカルの箱 {
        let mut 写した最小 = [f32::INFINITY; 3];
        let mut 写した最大 = [f32::NEG_INFINITY; 3];
        for 角 in self.八つの角() {
            let 写した角 = 配置で角を写す(配置, 角);
            for 軸 in 0..3 {
                写した最小[軸] = 写した最小[軸].min(写した角[軸]);
                写した最大[軸] = 写した最大[軸].max(写した角[軸]);
            }
        }
        群ローカルの箱 {
            最小: 写した最小,
            最大: 写した最大,
        }
    }

    /// 配置で写した、群のローカル座標系での任意姿勢の直方体。8つの角へ外接する軸平行の箱と違い、こちらは厳密である。
    /// 箱は部品のローカル座標系で軸平行であり、倍率も同じ座標系の軸に沿って掛かるため、回転を掛ける前は必ず軸平行の直方体のままだからである。
    /// 倍率の絶対値を取るのは、負の倍率が箱を裏返すだけで長さを変えないためである。
    pub fn 配置で任意姿勢の直方体へ写す(&self, 配置: &個体配置) -> Result<任意姿勢の直方体, カタログエラー> {
        let 写した中心 = 配置で角を写す(配置, self.部品ローカルの中心());
        let 倍率 = 配置.スケール();
        let 半分 = [0, 1, 2].map(|軸| メートル::生成する((self.最大[軸] - self.最小[軸]) * 0.5 * 倍率[軸].abs()));
        let 回転成分 = 配置.回転();
        let 回転 = クォータニオン::生成する(回転成分[0], 回転成分[1], 回転成分[2], 回転成分[3])
            .map_err(|_| 静的物理形状エラー::回転を正規化できない)?;
        let 中心 = 位置::生成する(
            メートル::生成する(写した中心[0]),
            メートル::生成する(写した中心[1]),
            メートル::生成する(写した中心[2]),
        );
        let 軸ごとの半分の長さ = 直方体の軸ごとの半分の長さ::生成する(半分).map_err(静的物理形状エラー::from)?;
        Ok(任意姿勢の直方体::生成する(中心, 回転, 軸ごとの半分の長さ).map_err(静的物理形状エラー::from)?)
    }

    fn 部品ローカルの中心(&self) -> [f32; 3] {
        [0, 1, 2].map(|軸| (self.最小[軸] + self.最大[軸]) * 0.5)
    }

    fn 八つの角(&self) -> [[f32; 3]; 8] {
        let mut 角一覧 = [[0.0_f32; 3]; 8];
        for (番号, 角) in 角一覧.iter_mut().enumerate() {
            for (軸, 成分) in 角.iter_mut().enumerate() {
                let 最大側か = (番号 >> 軸) & 1 == 1;
                *成分 = if 最大側か { self.最大[軸] } else { self.最小[軸] };
            }
        }
        角一覧
    }
}

/// 群のローカル座標系での軸平行な箱。配置で写した結果であり、部品のローカル座標系の箱とは別の型にする。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 群ローカルの箱 {
    最小: [f32; 3],
    最大: [f32; 3],
}

impl 群ローカルの箱 {
    pub fn 最小(&self) -> [f32; 3] {
        self.最小
    }

    pub fn 最大(&self) -> [f32; 3] {
        self.最大
    }

    /// 2つの箱へ外接する箱。建物全体の外形は、据えた全部品の箱をこの操作で畳んで作る。
    pub fn 相手を含む箱(&self, 相手: &Self) -> Self {
        let mut 最小 = [0.0; 3];
        let mut 最大 = [0.0; 3];
        for 軸 in 0..3 {
            最小[軸] = self.最小[軸].min(相手.最小[軸]);
            最大[軸] = self.最大[軸].max(相手.最大[軸]);
        }
        Self { 最小, 最大 }
    }

    /// 2つの箱が重なるか触れるか。**組み上げた部品が親と接していることの判定である。**
    /// 接している状態を落とさないよう、境界での接触も重なりとして数える。
    pub fn 相手と接するか(&self, 相手: &Self) -> bool {
        (0..3).all(|軸| self.最小[軸] <= 相手.最大[軸] && 相手.最小[軸] <= self.最大[軸])
    }

    /// 相手から最も離れている軸の隙間。接しているなら0以下になる。報告に載せて、どれだけ浮いたかを見せる。
    pub fn 相手との最大の隙間(&self, 相手: &Self) -> f32 {
        (0..3)
            .map(|軸| (相手.最小[軸] - self.最大[軸]).max(self.最小[軸] - 相手.最大[軸]))
            .fold(f32::NEG_INFINITY, f32::max)
    }
}
