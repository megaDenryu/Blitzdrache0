//! 部品の境界箱: 1つの部品が占める、部品のローカル座標系での軸平行な直方体。
//!
//! 部品定義が持たないのは、配置の計算に要らないためである。接合点だけで配置は決まる。**この箱が要るのは検証の側**であり、
//! 組み上げた部品が親と接しているか(宙に浮いていないか)を見るときに使う。
//!
//! 配置で写した箱を軸平行のまま扱うのは、回転が入ると厳密な箱が軸平行でなくなるためである。8つの角を写してから
//! 外接する軸平行の箱を取る形にすると、実際より大きい箱になる。**大きい側へ外れる誤差は、接触の判定を甘くする側へしか働かない。**
//! 接していないものを接していると誤って通すことはあるが、接しているものを落とすことはない。

use blitz_engine::個体配置;
use blitz_math::{メートル, 位置, 部品ローカル};

use super::corner_transform::配置で角を写す;
use super::error::カタログエラー;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 部品の境界箱 {
    最小: [f32; 3],
    最大: [f32; 3],
}

impl 部品の境界箱 {
    /// 最小が最大を超える箱を型付きエラーで拒む。向きの壊れた箱は接触の判定を無意味にする。
    pub fn 最小と最大から生成する(最小: [f32; 3], 最大: [f32; 3]) -> Result<Self, カタログエラー> {
        for 軸 in 0..3 {
            if !最小[軸].is_finite() || !最大[軸].is_finite() || 最小[軸] > 最大[軸] {
                return Err(カタログエラー::境界箱の最小が最大を超える { 軸 });
            }
        }
        Ok(Self { 最小, 最大 })
    }

    pub fn 最小の角(&self) -> 位置<部品ローカル> {
        角へ写す(self.最小)
    }

    pub fn 最大の角(&self) -> 位置<部品ローカル> {
        角へ写す(self.最大)
    }

    /// 配置で写した8つの角へ外接する、群のローカル座標系での軸平行な箱。
    pub fn 配置で写す(&self, 配置: &個体配置) -> 群ローカルの箱 {
        let mut 写した最小 = [f32::INFINITY; 3];
        let mut 写した最大 = [f32::NEG_INFINITY; 3];
        for 角 in self.八つの角() {
            let 写した角 = 配置で角を写す(配置, 角);
            for 軸 in 0..3 {
                写した最小[軸] = 写した最小[軸].min(写した角[軸]);
                写した最大[軸] = 写した最大[軸].max(写した角[軸]);
            }
        }
        群ローカルの箱 {
            最小: 写した最小,
            最大: 写した最大,
        }
    }

    fn 八つの角(&self) -> [[f32; 3]; 8] {
        let mut 角一覧 = [[0.0_f32; 3]; 8];
        for (番号, 角) in 角一覧.iter_mut().enumerate() {
            for (軸, 成分) in 角.iter_mut().enumerate() {
                let 最大側か = (番号 >> 軸) & 1 == 1;
                *成分 = if 最大側か { self.最大[軸] } else { self.最小[軸] };
            }
        }
        角一覧
    }
}

/// 群のローカル座標系での軸平行な箱。配置で写した結果であり、部品のローカル座標系の箱とは別の型にする。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 群ローカルの箱 {
    最小: [f32; 3],
    最大: [f32; 3],
}

impl 群ローカルの箱 {
    /// 2つの箱が重なるか触れるか。**組み上げた部品が親と接していることの判定である。**
    /// 接している状態を落とさないよう、境界での接触も重なりとして数える。
    pub fn 相手と接するか(&self, 相手: &Self) -> bool {
        (0..3).all(|軸| self.最小[軸] <= 相手.最大[軸] && 相手.最小[軸] <= self.最大[軸])
    }

    /// 相手から最も離れている軸の隙間。接しているなら0以下になる。報告に載せて、どれだけ浮いたかを見せる。
    pub fn 相手との最大の隙間(&self, 相手: &Self) -> f32 {
        (0..3)
            .map(|軸| (相手.最小[軸] - self.最大[軸]).max(self.最小[軸] - 相手.最大[軸]))
            .fold(f32::NEG_INFINITY, f32::max)
    }
}

fn 角へ写す(成分: [f32; 3]) -> 位置<部品ローカル> {
    位置::生成する(メートル::生成する(成分[0]), メートル::生成する(成分[1]), メートル::生成する(成分[2]))
}
