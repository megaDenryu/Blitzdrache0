//! 部品カタログ組み立て器: 部品を1つずつ積み、全部が揃ってから不変条件を検査してカタログを完成させる型。
//!
//! ビルダーを通す理由は「グラフだから」ではなく、**不変条件をいつ検査できるか**にある。対の相手がカタログに
//! 存在するかは、1件ずつ読んでいる途中では判定できない。半端な状態(相手が見つかっていないカタログ)を
//! 完成した型へ漏らさないため、完成の口をここへ1つだけ置く。
//! 参照: グローバルCLAUDE.md「デザインパターンの既定」、`_doc/設計/部品カタログと接合点.md`「部品カタログと展開器」

use crate::joint::{接合の様式, 接合種別};

use super::catalog::部品カタログ;
use super::definition::部品定義;
use super::error::{カタログエラー, 対の不足};
use super::part_id::部品ID;
use super::stored_part::収蔵部品;

pub struct 部品カタログ組み立て器 {
    積んだ部品一覧: Vec<収蔵部品>,
}

impl 部品カタログ組み立て器 {
    pub fn 空から始める() -> Self {
        Self {
            積んだ部品一覧: Vec::new()
        }
    }

    /// 同じ識別子の部品を2件積むことを積んだ時点で拒む。組み上げまで待つと、どちらの定義が残ったのかが分からなくなる。
    pub fn 部品を1つ積む(&mut self, 識別子: 部品ID, 定義: 部品定義) -> Result<(), カタログエラー> {
        if self.積んだ部品一覧.iter().any(|部品| 部品.識別子() == &識別子) {
            return Err(カタログエラー::部品IDが重複している {
                部品の識別子: 識別子
            });
        }
        self.積んだ部品一覧.push(収蔵部品::生成する(識別子, 定義));
        Ok(())
    }

    /// 不足を1件目で止めず全件集める。1件直して再実行するたびに次の1件が出る形だと、直しの往復が件数だけ要る。
    pub fn 組み上げる(self) -> Result<部品カタログ, カタログエラー> {
        let 不足一覧 = self.噛み合う相手が無い接合点を集める();
        if !不足一覧.is_empty() {
            return Err(カタログエラー::噛み合う相手がカタログに無い { 不足一覧 });
        }
        Ok(部品カタログ::検査済みの一覧から生成する(self.積んだ部品一覧))
    }

    /// 噛み合える相手が複数ある種別は、そのうち1つでもカタログに在れば繋げる先がある。
    ///
    /// 様式が未定の種別は相手の在否を問わない。未定の接合は組む地点で必ず拒まれるため、相手が揃っていても組めず、
    /// 揃っていないことを不足として並べても直しようが無い。**片側だけ先に収蔵された対が、収蔵そのものを止めるのを避ける。**
    /// 扉の吊り元は壁の部品に在るが、噛み合う扉板の吊り軸を持つ部品はまだ実物になっていない。
    /// 片側が実データに現れていないことは、被覆の報告が未出現の行として受け持つ。
    fn 噛み合う相手が無い接合点を集める(&self) -> Vec<対の不足> {
        let 宣言された種別一覧 = self.宣言された種別を集める();
        let mut 不足一覧 = Vec::new();
        for 部品 in &self.積んだ部品一覧 {
            for 接合点 in 部品.定義().接合点一覧() {
                if 接合点.種別().様式() == 接合の様式::未定 {
                    continue;
                }
                let 相手が在る = 接合点
                    .種別()
                    .噛み合う相手の種別一覧()
                    .iter()
                    .any(|相手| 宣言された種別一覧.contains(相手));
                if 相手が在る {
                    continue;
                }
                不足一覧.push(対の不足 {
                    部品の識別子: 部品.識別子().clone(),
                    接合点の名前: 接合点.名前().clone(),
                    種別: 接合点.種別(),
                });
            }
        }
        不足一覧
    }

    fn 宣言された種別を集める(&self) -> Vec<接合種別> {
        let mut 種別一覧: Vec<接合種別> = self
            .積んだ部品一覧
            .iter()
            .flat_map(|部品| 部品.定義().接合点一覧())
            .map(|接合点| 接合点.種別())
            .collect();
        種別一覧.sort_unstable();
        種別一覧.dedup();
        種別一覧
    }
}
