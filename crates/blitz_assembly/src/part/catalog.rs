//! 部品カタログ: 組み上げを通った全部品の台帳。この値が在ることが、全部品の対の相手が揃っていることの証拠である。
//!
//! 生成の口を持たないのは、全部品を読み終えるまで不変条件を検査できないためである。対の相手がカタログに
//! 存在するかは、1件ずつ読んでいる途中では判定できない。作れるのは`部品カタログ組み立て器`だけである。

use crate::joint::{全接合種別, 接合種別};

use super::stored_part::収蔵部品;

/// 1つの接合種別と、カタログ全体でその種別を宣言している接合点の件数。0件の種別も落とさずに持つ。
/// 0件を落とすと、検査が空振りしている範囲が報告から消える。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接合種別ごとの員数 {
    pub 種別: 接合種別,
    pub 件数: usize,
}

#[derive(Debug, Clone, PartialEq)]
pub struct 部品カタログ {
    収蔵部品一覧: Vec<収蔵部品>,
}

impl 部品カタログ {
    /// 組み立て器だけが呼べる。検査を通った一覧をそのまま受け取る。
    pub(super) fn 検査済みの一覧から生成する(収蔵部品一覧: Vec<収蔵部品>) -> Self {
        Self { 収蔵部品一覧 }
    }

    pub fn 部品数(&self) -> usize {
        self.収蔵部品一覧.len()
    }

    pub fn 収蔵部品一覧(&self) -> &[収蔵部品] {
        &self.収蔵部品一覧
    }

    pub fn 接合点の総数(&self) -> usize {
        self.収蔵部品一覧.iter().map(|部品| 部品.定義().接合点数()).sum()
    }

    /// 全種別を宣言の順で並べ、それぞれの件数を数える。件数が0の種別が、実データで検査が空振りしている範囲である。
    pub fn 種別ごとの員数一覧(&self) -> Vec<接合種別ごとの員数> {
        全接合種別
            .into_iter()
            .map(|種別| 接合種別ごとの員数 {
                種別,
                件数: self.ある種別の件数を数える(種別),
            })
            .collect()
    }

    fn ある種別の件数を数える(&self, 種別: 接合種別) -> usize {
        self.収蔵部品一覧
            .iter()
            .flat_map(|部品| 部品.定義().接合点一覧())
            .filter(|接合点| 接合点.種別() == 種別)
            .count()
    }
}
