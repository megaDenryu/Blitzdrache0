//! 部品の境界箱を配置で任意姿勢の直方体へ写す計算の試験。
//!
//! 天頂まわりの半回転と軸ごとに違う倍率を同時に掛けるのは、倍率が部品のローカル座標系の軸に沿って掛かり、
//! そのあとに回転が掛かるという順序を固定するためである。順序を取り違えると、東西へ伸ばした箱が南北へ伸びる。
//! この配置では回転が軸を入れ替えるだけであるため、外接する軸平行の箱が中心と半分の長さから直に求まり、
//! 任意姿勢の直方体と既存の軸平行の箱が同じ物体を指していることも同時に確かめられる。

#![allow(clippy::unwrap_used)]

use blitz_engine::個体配置;

use super::bounding_box::部品の境界箱;

fn 壁の箱() -> 部品の境界箱 {
    部品の境界箱::最小と最大から生成する([-1.0, 0.0, -0.5], [1.0, 2.0, 0.5]).unwrap()
}

/// 天頂まわりの半回転で東へ2倍に伸ばした配置。半回転は4成分が厳密に表せるため、丸めが答えへ入らない。
fn 半回転して東へ伸ばす配置() -> 個体配置 {
    個体配置::生成する([10.0, 3.0, -4.0], [0.0, 1.0, 0.0, 0.0], [2.0, 1.0, 1.0]).unwrap()
}

#[test]
fn 中心は倍率と回転と平行移動をこの順に受ける() {
    let 直方体 = 壁の箱().配置で任意姿勢の直方体へ写す(&半回転して東へ伸ばす配置()).unwrap();
    let 中心 = 直方体.中心();
    assert_eq!((中心.x().値(), 中心.y().値(), 中心.z().値()), (10.0, 4.0, -4.0));
}

#[test]
fn 軸ごとの半分の長さは部品ローカルの軸に沿って倍率を受ける() {
    let 直方体 = 壁の箱().配置で任意姿勢の直方体へ写す(&半回転して東へ伸ばす配置()).unwrap();
    let 半分 = 直方体.軸ごとの半分の長さ();
    assert_eq!((半分.x().値(), 半分.y().値(), 半分.z().値()), (2.0, 1.0, 0.5));
    assert_eq!(直方体.回転().境界用xyzw配列(), [0.0, 1.0, 0.0, 0.0]);
}

#[test]
fn 負の倍率は長さを変えず箱を裏返すだけである() {
    let 配置 = 個体配置::生成する([0.0; 3], [0.0, 0.0, 0.0, 1.0], [-2.0, 1.0, 1.0]).unwrap();
    let 直方体 = 壁の箱().配置で任意姿勢の直方体へ写す(&配置).unwrap();
    assert_eq!(直方体.軸ごとの半分の長さ().x().値(), 2.0);
}

#[test]
fn 軸を入れ替えるだけの回転では外接する軸平行の箱と一致する() {
    let 配置 = 半回転して東へ伸ばす配置();
    let 直方体 = 壁の箱().配置で任意姿勢の直方体へ写す(&配置).unwrap();
    let 軸平行の箱 = 壁の箱().配置で写す(&配置);
    let 中心 = [直方体.中心().x().値(), 直方体.中心().y().値(), 直方体.中心().z().値()];
    let 半分 = [
        直方体.軸ごとの半分の長さ().x().値(),
        直方体.軸ごとの半分の長さ().y().値(),
        直方体.軸ごとの半分の長さ().z().値(),
    ];
    for 軸 in 0..3 {
        assert!((軸平行の箱.最小()[軸] - (中心[軸] - 半分[軸])).abs() < 1.0e-6);
        assert!((軸平行の箱.最大()[軸] - (中心[軸] + 半分[軸])).abs() < 1.0e-6);
    }
}
