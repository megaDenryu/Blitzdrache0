//! 部品定義: 1つの部品が宣言する接合点の束。
//!
//! 名前の一意性をこの型が確かめるのは、組み立て規則が接合点を名前で指すためである。同じ名前が2つあると、
//! 規則が指す先が実行時まで決まらない。接合点が1件以上あることをここで求めないのは、その規則の正本が
//! 入力契約の検査(`cargo xtask check-glb --part`)にあり、2箇所へ書くと片方だけを直した食い違いが出るためである。

use crate::joint::{接合点, 接合点エラー};

#[derive(Debug, Clone, PartialEq)]
pub struct 部品定義 {
    接合点一覧: Vec<接合点>,
}

impl 部品定義 {
    pub fn 生成する(接合点一覧: Vec<接合点>) -> Result<Self, 接合点エラー> {
        for (添字, 接合点) in 接合点一覧.iter().enumerate() {
            let 先に同名がある = 接合点一覧[..添字].iter().any(|先の接合点| 先の接合点.名前() == 接合点.名前());
            if 先に同名がある {
                return Err(接合点エラー::接合点の名前が重複している {
                    名前: 接合点.名前().綴り().to_string(),
                });
            }
        }
        Ok(Self { 接合点一覧 })
    }

    pub fn 接合点一覧(&self) -> &[接合点] {
        &self.接合点一覧
    }

    pub fn 接合点数(&self) -> usize {
        self.接合点一覧.len()
    }
}
