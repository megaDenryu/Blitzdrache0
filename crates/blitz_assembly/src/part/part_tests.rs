//! 部品とカタログの試験。担当するのは、組み立て器が全部品を読み終えてから対の相手を検査することと、
//! 不足を1件目で止めず全件集めることと、員数の一覧が0件の種別を落とさないことを固定することである。
//! 材料に実データの積層の鎖(基礎の上面と2階の下面)と煙突を使い、検査が通る形と通らない形を実物の値で示す。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, 位置, 方向, 部品ローカル};

use crate::joint::{接合点, 接合点名, 接合種別, 接合面の姿勢, 接合面の形と寸法};

use super::catalog_builder::部品カタログ組み立て器;
use super::definition::部品定義;
use super::error::カタログエラー;
use super::part_id::部品ID;

fn 接合点を作る(名前: &str, 種別: 接合種別, 上向きか: bool) -> 接合点 {
    let 天地の符号 = if 上向きか { 1.0 } else { -1.0 };
    let 向き = 方向::生成する(0.0, 天地の符号, 0.0).unwrap();
    let 姿勢 = 接合面の姿勢::生成する(向き, 方向::生成する(0.0, 0.0, 1.0).unwrap()).unwrap();
    接合点::生成する(
        接合点名::生成する(名前).unwrap(),
        種別,
        位置::<部品ローカル>::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0)),
        姿勢,
        接合面の形と寸法::矩形を生成する(メートル::生成する(6.0), メートル::生成する(5.0)).unwrap(),
    )
}

fn 部品を作る(接合点一覧: Vec<接合点>) -> 部品定義 {
    部品定義::生成する(接合点一覧).unwrap()
}

fn 基礎と2階のカタログを組む() -> 部品カタログ組み立て器 {
    let mut 組み立て器 = 部品カタログ組み立て器::空から始める();
    組み立て器
        .部品を1つ積む(
            部品ID::生成する("基礎").unwrap(),
            部品を作る(vec![接合点を作る("上面", 接合種別::上面積層, true)]),
        )
        .unwrap();
    組み立て器
        .部品を1つ積む(
            部品ID::生成する("2階").unwrap(),
            部品を作る(vec![接合点を作る("下面", 接合種別::下面積層, false)]),
        )
        .unwrap();
    組み立て器
}

#[test]
fn 対の相手が揃っていればカタログが組み上がる() {
    let カタログ = 基礎と2階のカタログを組む().組み上げる().unwrap();
    assert_eq!(カタログ.部品数(), 2);
    assert_eq!(カタログ.接合点の総数(), 2);
}

#[test]
fn 対の相手が無い接合点を全件集めて拒む() {
    let mut 組み立て器 = 部品カタログ組み立て器::空から始める();
    組み立て器
        .部品を1つ積む(
            部品ID::生成する("煙突").unwrap(),
            部品を作る(vec![
                接合点を作る("下面", 接合種別::下面積層, false),
                接合点を作る("壁面密着面", 接合種別::壁面取付, true),
            ]),
        )
        .unwrap();
    match 組み立て器.組み上げる() {
        Err(カタログエラー::対の相手がカタログに無い { 不足一覧 }) => assert_eq!(不足一覧.len(), 2),
        その他 => panic!("対の相手の不足を全件集めるはずが: {その他:?}"),
    }
}

#[test]
fn 同じ部品idを2件積むことを積んだ時点で拒む() {
    let mut 組み立て器 = 基礎と2階のカタログを組む();
    let 結果 = 組み立て器.部品を1つ積む(部品ID::生成する("基礎").unwrap(), 部品を作る(vec![]));
    assert!(matches!(結果, Err(カタログエラー::部品IDが重複している { .. })));
}

#[test]
fn 同じ名前の接合点を持つ部品定義を拒む() {
    let 重複 = vec![
        接合点を作る("上面", 接合種別::上面積層, true),
        接合点を作る("上面", 接合種別::下面積層, false),
    ];
    assert!(部品定義::生成する(重複).is_err());
}

/// 0件の種別を落とすと、検査が空振りしている範囲が報告から消える。
#[test]
fn 員数の一覧は0件の種別も落とさない() {
    let カタログ = 基礎と2階のカタログを組む().組み上げる().unwrap();
    let 一覧 = カタログ.種別ごとの員数一覧();
    assert_eq!(一覧.len(), 12);
    assert_eq!(一覧.iter().filter(|員数| 員数.件数 == 0).count(), 10);
}
