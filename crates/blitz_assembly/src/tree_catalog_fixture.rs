//! 木の試験の材料のうち、部品の識別子と3部品のカタログ。接合点の値は`tree_fixture`が持つ。
//!
//! 接合点と分けているのは、変わる理由が違うためである。接合点はBlender側が部品を直すと変わり、
//! カタログの組み方は部品の件数が増えると変わる。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use crate::part::{部品ID, 部品カタログ, 部品カタログ組み立て器, 部品定義};
use crate::tree_fixture::{幹の基部, 幹の頂部, 枝の根元, 枝の生え口, 葉房の根元, 頂芽};

/// 幹の部品の識別子。木の手順が根に据える部品である。
pub(crate) fn 幹の部品() -> 部品ID {
    識別子("幹の一節")
}

pub(crate) fn 枝の部品() -> 部品ID {
    識別子("大枝")
}

pub(crate) fn 葉房の部品() -> 部品ID {
    識別子("葉房")
}

pub(crate) fn 識別子(綴り: &str) -> 部品ID {
    部品ID::生成する(綴り).unwrap()
}

/// 実データの樫の木3部品を写したカタログ。幹は基部と頂部と枝の生え口、枝は根元と頂芽、葉房は根元を持つ。
pub(crate) fn 樫の木のカタログ() -> 部品カタログ {
    let mut 組み立て器 = 部品カタログ組み立て器::空から始める();
    let 部品一覧 = [
        (幹の部品(), vec![幹の基部(), 幹の頂部(), 枝の生え口()]),
        (枝の部品(), vec![枝の根元(), 頂芽()]),
        (葉房の部品(), vec![葉房の根元()]),
    ];
    for (識別子, 接合点一覧) in 部品一覧 {
        組み立て器.部品を1つ積む(識別子, 部品定義::生成する(接合点一覧).unwrap()).unwrap();
    }
    組み立て器.組み上げる().unwrap()
}
