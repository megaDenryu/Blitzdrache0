//! 接合種別の対応表の試験。担当するのは、誰と誰が噛み合えるかの表が対称で抜けを持たず、
//! 自分自身と噛み合う種別が相互の1件だけであることを固定することである。
//! 何を検査するかの割り当ては`joint_kind_style_tests`が担当する。
//!
//! 対応表の対称性を試験で固定するのは、種別を足すときに片方向だけ書き足す誤りが、
//! 「噛み合う相手がカタログに無い」という遠い場所の失敗として現れるためである。
//! **相手が複数ある種別が入って、対称性が一覧の相互参照になった。** 片側の一覧へ足して逆側へ足し忘れる形は、
//! 表を目で読んでも見つけにくい。

#![allow(clippy::unwrap_used)]

use super::joint_kind::{全接合種別, 接合種別};

#[test]
fn 噛み合う相手の一覧は互いに相手を含む() {
    for 種別 in 全接合種別 {
        for 相手 in 種別.噛み合う相手の種別一覧() {
            assert!(相手.噛み合うか(種別), "{種別}は{相手}と噛み合うのに、{相手}の一覧に{種別}が無い");
        }
    }
}

#[test]
fn 噛み合う相手を1つも持たない種別は無い() {
    for 種別 in 全接合種別 {
        assert!(!種別.噛み合う相手の種別一覧().is_empty(), "{種別}が噛み合う相手を1つも持たない");
    }
}

/// 自分自身と噛み合う種別を相互と呼ぶ。ベイの継ぎ口だけがそれであり、他の種別が相互になるのは
/// 対応表の書き誤り(取り付ける側と取り付けられる側を同じ枝へ書いた形)である。
#[test]
fn 自分自身と噛み合うのはベイの継ぎ口だけである() {
    let 相互の種別一覧: Vec<接合種別> = 全接合種別.into_iter().filter(|種別| 種別.噛み合うか(*種別)).collect();
    assert_eq!(相互の種別一覧, vec![接合種別::ベイの継ぎ口]);
}

/// 木では枝の根元が幹の先にも枝の途中にも枝の先にも付く。1対1の表ではこの木を表せない。
#[test]
fn 枝の根元は幹頂部と枝の生え口と頂芽の3つへ付く() {
    assert!(接合種別::枝の根元.噛み合うか(接合種別::幹頂部));
    assert!(接合種別::枝の根元.噛み合うか(接合種別::枝の生え口));
    assert!(接合種別::枝の根元.噛み合うか(接合種別::頂芽));
    assert!(接合種別::頂芽.噛み合うか(接合種別::葉房の根元));
}

/// 屋根面と壁面は別の種別であり、互いに噛み合わない。噛み合うようにすると、
/// 語を分けた意味が消えて屋根の傾斜面へ壁用の差込が付く。
#[test]
fn 屋根面と壁面は互いに噛み合わない() {
    assert!(!接合種別::屋根面取付.噛み合うか(接合種別::壁面差込));
    assert!(!接合種別::壁面取付.噛み合うか(接合種別::屋根面差込));
}

/// 骨格の枠へ壁1枚をはめる関係と、壁の面へ出窓や煙突を差し込む関係は別物である。噛み合うようにすると、
/// 壁が壁へ差し込まれる組み方が通り、はめ口の寸法の一致を課した意味が消える。
#[test]
fn 壁の外枠は壁面の対のどちらとも噛み合わない() {
    assert!(!接合種別::壁の外枠.噛み合うか(接合種別::壁面取付));
    assert!(!接合種別::壁の外枠.噛み合うか(接合種別::壁面差込));
    assert!(!接合種別::壁のはめ口.噛み合うか(接合種別::壁面差込));
}

/// ベイの継ぎ口と壁のはめ口は骨格の同じ物理面へ重ねて宣言されている。噛み合うようにすると、
/// 壁が隣のベイの継ぎ口へはまる組み方と、隣のベイが壁のはめ口へ継がる組み方が通り、
/// 同じ面へ壁と隣のベイが二重に入る配置を型で防げなくなる。
#[test]
fn ベイの継ぎ口は壁の対のどちらとも噛み合わない() {
    assert!(!接合種別::ベイの継ぎ口.噛み合うか(接合種別::壁のはめ口));
    assert!(!接合種別::ベイの継ぎ口.噛み合うか(接合種別::壁の外枠));
}
