//! 接合点の生成の失敗。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! 未知の種別の綴りを枝が持つのは、この誤りの読み手がBlender側の作者であり、
//! 「何と綴られていたか」が分からないと直す先が決まらないためである。
//! `方向として成り立たない`が項目名を持つのも同じ理由である。向きと上方向は同じ形をしており、区別が無いと直す先が決まらない。

use blitz_math::方向エラー;
use thiserror::Error;

#[derive(Debug, Clone, PartialEq, Error)]
pub enum 接合点エラー {
    #[error("接合点の名前が空である")]
    名前が空,

    #[error("未知の接合種別である: {綴り}")]
    未知の接合種別 { 綴り: String },

    #[error("接合点の{項目名}が方向として成り立たない: {誤り}")]
    方向として成り立たない {
        項目名: &'static str, // 向きと上方向のどちらが破れたかを言う
        #[source]
        誤り: 方向エラー,
    },

    #[error("接合点の向きと上方向が直交していない: {誤り}")]
    向きと上方向が直交していない {
        #[source]
        誤り: 方向エラー,
    },

    #[error("接合面の{辺名}が正で有限でない: {値}メートル")]
    接合面の寸法が正で有限でない { 辺名: &'static str, 値: f32 },

    #[error("同じ部品の中で接合点の名前が重なっている: {名前}")]
    接合点の名前が重複している { 名前: String },

    #[error("接合面上の位置の{成分名}が有限でない: {値}メートル")]
    接合面上の位置が有限でない { 成分名: &'static str, 値: f32 },

    #[error("法線方向のずらしが有限でない: {値}メートル")]
    法線方向のずらしが有限でない { 値: f32 },
}
