//! 接合面の姿勢: 接合面がどちらを向き、どちらが天地かを表す。向きと上方向から作り、面上の回転の自由度を残さない。
//!
//! 法線1本では、その軸まわりの回転が決まらない。壁へ出窓を嵌めるとき、出窓が横倒しでも法線の条件は満たされる。
//! 建築では窓の天地と屋根の勾配方向が常に意味を持つため、この自由度を残してはならない。
//!
//! 横軸を生成の時点で求めて保持するのは、接合面の幅がどの軸に沿うかが規約で決まっており、
//! 使うたびに外積を書き直すと規約の写しが散るためである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合面の幅と高さがどの軸に対応するか」

use blitz_math::{方向, 部品ローカル};

use super::error::接合点エラー;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接合面の姿勢 {
    法線: 方向<部品ローカル>,
    縦軸: 方向<部品ローカル>,
    横軸: 方向<部品ローカル>,
}

impl 接合面の姿勢 {
    /// 直交していない向きと上方向を型付きエラーで拒む。単位方向どうしの外積の長さはなす角の正弦であるから、
    /// 横軸を求める計算がそのまま直交性の検査になる。
    pub fn 生成する(向き: 方向<部品ローカル>, 上方向: 方向<部品ローカル>) -> Result<Self, 接合点エラー> {
        let 横軸 = 上方向
            .直交する方向を求める(&向き)
            .map_err(|誤り| 接合点エラー::向きと上方向が直交していない { 誤り })?;
        Ok(Self {
            法線: 向き,
            縦軸: 上方向,
            横軸,
        })
    }

    /// 接合面の外向き法線。宣言の`向き`そのものである。
    pub fn 法線(&self) -> 方向<部品ローカル> {
        self.法線
    }

    /// 接合面の高さが沿う軸。宣言の`上方向`そのものである。
    pub fn 縦軸(&self) -> 方向<部品ローカル> {
        self.縦軸
    }

    /// 接合面の幅が沿う軸。上方向と向きの外積であり、横軸と縦軸と法線はこの順で右手系をなす。
    pub fn 横軸(&self) -> 方向<部品ローカル> {
        self.横軸
    }
}
