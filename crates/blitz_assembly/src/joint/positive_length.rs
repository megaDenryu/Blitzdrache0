//! 正で有限な長さ: 接合面の辺と直径が満たす不変条件を1箇所で持つ型。
//!
//! 判別共用体のバリアントのフィールドは外から直に書けるため、検証を生成の口だけに置くと、
//! 別の口から不変条件を回避できてしまう。**中身をこの型にすることで、どのバリアントをどう書いても
//! 正で有限であることが保たれる。** 形を1つ足すたびに同じ検証を書き直す形も、これで消える。

use blitz_math::メートル;

use super::error::接合点エラー;

#[derive(Debug, Clone, Copy, PartialEq)]
#[repr(transparent)]
pub struct 正で有限な長さ(メートル);

impl 正で有限な長さ {
    /// 零・負・非有限を型付きエラーで拒む。どれも噛み合いの判定が成り立たない値であり、
    /// 受け入れると「面が無い接合点」が組み立てへ流れる。
    /// 辺名を受け取るのは、幅と高さと直径が同じ形をしており、区別が無いと読み手が直す先を決められないためである。
    pub fn 生成する(辺名: &'static str, 長さ: メートル) -> Result<Self, 接合点エラー> {
        let 値 = 長さ.値();
        if 値.is_finite() && 値 > 0.0 {
            return Ok(Self(長さ));
        }
        Err(接合点エラー::接合面の寸法が正で有限でない { 辺名, 値 })
    }

    pub fn 値(self) -> メートル {
        self.0
    }
}
