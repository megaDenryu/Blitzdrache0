//! 接合種別の対応表と様式の割り当ての試験。担当するのは、対応が対称であることと、様式の割り当てが
//! 実データの裏づけを持つ4種別に限られていることを固定することである。
//!
//! 対応表の対称性を試験で固定するのは、種別を足すときに片方向だけ書き足す誤りが、
//! 「対の相手がカタログに無い」という遠い場所の失敗として現れるためである。

#![allow(clippy::unwrap_used)]

use super::joint_kind::{全接合種別, 接合種別};
use super::mating_style::接合の様式;

#[test]
fn 対になる種別を2回たどると元へ戻る() {
    for 種別 in 全接合種別 {
        assert_eq!(種別.対になる種別().対になる種別(), 種別, "{種別}の対応が対称でない");
    }
}

#[test]
fn 対になる種別は自分自身でない() {
    for 種別 in 全接合種別 {
        assert_ne!(種別.対になる種別(), 種別, "{種別}が自分自身と対になっている");
    }
}

/// 実データの裏づけがあるのは積層2種別と取付2種別だけである。残りは未定でなければならない。
/// ここを緩めると、寸法の合わない種別が黙って積層か取付として検査を通る。
#[test]
fn 様式が決まっているのは実データの裏づけがある4種別だけである() {
    let 決まっている種別一覧: Vec<接合種別> = 全接合種別.into_iter().filter(|種別| 種別.様式() != 接合の様式::未定).collect();
    assert_eq!(
        決まっている種別一覧,
        vec![接合種別::上面積層, 接合種別::下面積層, 接合種別::壁面取付, 接合種別::壁面差込]
    );
}

/// 対の2つは同じ様式に属し、取付なら役割が互いに逆でなければならない。
/// 役割が同じ側どうしになると、どちらが面を受け入れるのかが決まらないまま包含の判定へ進む。
#[test]
fn 対になる2つの種別は同じ様式で役割が逆である() {
    for 種別 in 全接合種別 {
        let 相手 = 種別.対になる種別();
        match (種別.様式(), 相手.様式()) {
            (接合の様式::積層, 接合の様式::積層) | (接合の様式::未定, 接合の様式::未定) => {}
            (接合の様式::取付 { 役割: 自分 }, 接合の様式::取付 { 役割: 相手の役割 }) => {
                assert_ne!(自分, 相手の役割, "{種別}と対の相手で取付の役割が同じ側になっている");
            }
            (自分, 相手の様式) => panic!("{種別}と対の相手で様式が食い違う: {自分:?}と{相手の様式:?}"),
        }
    }
}
