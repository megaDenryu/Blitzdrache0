//! 接合種別の対応表と様式の割り当ての試験。担当するのは、対応が対称であることと、様式の割り当てが
//! 実データの裏づけを持つ種別に限られていることを固定することである。
//!
//! 対応表の対称性を試験で固定するのは、種別を足すときに片方向だけ書き足す誤りが、
//! 「噛み合う相手がカタログに無い」という遠い場所の失敗として現れるためである。
//! **相手が複数ある種別が入って、対称性が一覧の相互参照になった。** 片側の一覧へ足して逆側へ足し忘れる形は、
//! 表を目で読んでも見つけにくい。

#![allow(clippy::unwrap_used)]

use super::joint_kind::{全接合種別, 接合種別};
use super::mating_style::接合の様式;

#[test]
fn 噛み合う相手の一覧は互いに相手を含む() {
    for 種別 in 全接合種別 {
        for 相手 in 種別.噛み合う相手の種別一覧() {
            assert!(相手.噛み合うか(種別), "{種別}は{相手}と噛み合うのに、{相手}の一覧に{種別}が無い");
        }
    }
}

#[test]
fn 噛み合う相手を1つも持たない種別は無い() {
    for 種別 in 全接合種別 {
        assert!(!種別.噛み合う相手の種別一覧().is_empty(), "{種別}が噛み合う相手を1つも持たない");
    }
}

#[test]
fn 自分自身と噛み合う種別は無い() {
    for 種別 in 全接合種別 {
        assert!(!種別.噛み合うか(種別), "{種別}が自分自身と噛み合う");
    }
}

/// 木では枝の根元が幹の先にも枝の途中にも枝の先にも付く。1対1の表ではこの木を表せない。
#[test]
fn 枝の根元は幹頂部と枝の生え口と頂芽の3つへ付く() {
    assert!(接合種別::枝の根元.噛み合うか(接合種別::幹頂部));
    assert!(接合種別::枝の根元.噛み合うか(接合種別::枝の生え口));
    assert!(接合種別::枝の根元.噛み合うか(接合種別::頂芽));
    assert!(接合種別::頂芽.噛み合うか(接合種別::葉房の根元));
}

/// 何を検査すれば噛み合うかが決まっていないのは、実データが2つの様式のどちらでも合格しない屋根の2種別だけである。
/// ここを緩めると、寸法の合わない種別が黙って一致か包含として検査を通る。
#[test]
fn 様式がまだ決まっていないのは屋根の棟と屋根の笠だけである() {
    let 未定の種別一覧: Vec<接合種別> = 全接合種別.into_iter().filter(|種別| 種別.様式() == 接合の様式::未定).collect();
    assert_eq!(未定の種別一覧, vec![接合種別::屋根の棟, 接合種別::屋根の笠]);
}

/// 屋根面の対は、面が傾いていても壁面の対とまったく同じ検査を受ける。傾きは接合面の姿勢が表し、
/// 様式は関知しない。ここが食い違うと、傾斜面への差し込みだけ別の検査を通る道ができる。
#[test]
fn 屋根面の対は壁面の対と同じ様式である() {
    assert_eq!(接合種別::屋根面取付.様式(), 接合種別::壁面取付.様式());
    assert_eq!(接合種別::屋根面差込.様式(), 接合種別::壁面差込.様式());
}

/// 屋根面と壁面は別の種別であり、互いに噛み合わない。噛み合うようにすると、
/// 語を分けた意味が消えて屋根の傾斜面へ壁用の差込が付く。
#[test]
fn 屋根面と壁面は互いに噛み合わない() {
    assert!(!接合種別::屋根面取付.噛み合うか(接合種別::壁面差込));
    assert!(!接合種別::壁面取付.噛み合うか(接合種別::屋根面差込));
}

/// 噛み合う2つは同じ様式に属し、包含なら役割が互いに逆でなければならない。
/// 役割が同じ側どうしになると、どちらが面を受け入れるのかが決まらないまま包含の判定へ進む。
#[test]
fn 噛み合う2つの種別は同じ様式で役割が逆である() {
    for 種別 in 全接合種別 {
        for 相手 in 種別.噛み合う相手の種別一覧() {
            match (種別.様式(), 相手.様式()) {
                (接合の様式::一致, 接合の様式::一致) | (接合の様式::未定, 接合の様式::未定) => {}
                (接合の様式::包含 { 役割: 自分 }, 接合の様式::包含 { 役割: 相手の役割 }) => {
                    assert_ne!(自分, 相手の役割, "{種別}と{相手}で包含の役割が同じ側になっている");
                }
                (自分, 相手の様式) => panic!("{種別}と{相手}で様式が食い違う: {自分:?}と{相手の様式:?}"),
            }
        }
    }
}
