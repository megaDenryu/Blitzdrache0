//! 接合点の語彙の試験。担当するのは、対応表が対称であることと、様式の割り当てが実データの裏づけを持つ4種別に
//! 限られていることと、宣言の破れが型付きエラーで止まることを固定することである。
//!
//! 対応表の対称性を試験で固定するのは、種別を足すときに片方向だけ書き足す誤りが、
//! 「対の相手がカタログに無い」という遠い場所の失敗として現れるためである。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, 方向, 部品ローカル};

use super::error::接合点エラー;
use super::face_pose::接合面の姿勢;
use super::face_size::接合面の形と寸法;
use super::joint_kind::{全接合種別, 接合種別};
use super::joint_name::接合点名;

fn 方向を作る(x: f32, y: f32, z: f32) -> 方向<部品ローカル> {
    方向::生成する(x, y, z).unwrap()
}

#[test]
fn 綴りは種別と往復する() {
    for 種別 in 全接合種別 {
        assert_eq!(接合種別::綴りから読み取る(種別.綴り()).unwrap(), 種別);
    }
}

#[test]
fn 未知の綴りは綴りを添えた型付きエラーになる() {
    assert_eq!(
        接合種別::綴りから読み取る("上面つみかさね"),
        Err(接合点エラー::未知の接合種別 {
            綴り: "上面つみかさね".to_string()
        })
    );
}

#[test]
fn 空の接合点名を拒む() {
    assert_eq!(接合点名::生成する("   "), Err(接合点エラー::名前が空));
}

#[test]
fn 直交していない向きと上方向を拒む() {
    let 向き = 方向を作る(0.0, 1.0, 0.0);
    assert!(matches!(
        接合面の姿勢::生成する(向き, 向き),
        Err(接合点エラー::向きと上方向が直交していない { .. })
    ));
}

/// 実データの上面の接合点(向きが上、上方向が奥、幅6.0がX方向)で、横軸がX軸に沿うことを固定する。
#[test]
fn 上面の接合面の姿勢は横軸をx軸に沿わせる() {
    let 姿勢 = 接合面の姿勢::生成する(方向を作る(0.0, 1.0, 0.0), 方向を作る(0.0, 0.0, 1.0)).unwrap();
    assert_eq!(姿勢.横軸(), 方向を作る(-1.0, 0.0, 0.0));
    assert_eq!(姿勢.縦軸(), 方向を作る(0.0, 0.0, 1.0));
    assert_eq!(姿勢.法線(), 方向を作る(0.0, 1.0, 0.0));
}

#[test]
fn 零や負の接合面の寸法を拒む() {
    for 幅 in [0.0, -1.0, f32::NAN] {
        assert!(接合面の形と寸法::矩形を生成する(メートル::生成する(幅), メートル::生成する(1.0)).is_err());
    }
}
