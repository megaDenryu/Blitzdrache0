//! 法線方向のずらし: 取付のとき、向かい合わせた位置から親の接合面の法線方向へ子を寄せる量。
//! 正が離す側、負が食い込ませる側である。
//!
//! **この次元が要るのは、部品を互いに食い込ませて組むことが確立した運用だからである。** 面をぴったり合わせると
//! 重複した頂点の統合が非多様体を作るため、部品は数センチから数十センチ食い込ませて組む。
//! **接合点の宣言は部品の表面のままにし、食い込みは配置の決定としてこの値が持つ。** 2つを混ぜると、
//! 接合点が実物の表面から浮いた宣言になり、部品を単体で検査したときに宣言と実物が食い違う。
//!
//! 値域を持たないのは、離しすぎた配置を型でなく検査に落とさせるためである。正のずらしで子が親から離れれば、
//! 組み上げた部品が親と接しているかの検査が、ずらしを適用した後の位置で落とす。型で幅を決めると、
//! その幅の根拠を部品ごとに持てないまま1つの数へ畳むことになる。
//!
//! 接合面上の位置と別の値にするのは、役割が違うためである。面上の位置は親の接合面へ収まることを求められ、
//! はみ出しの判定を受ける。こちらはどの判定も受けず、噛み合いを確かめた後の平行移動にだけ効く。
//! 参照: `_doc/設計/部品カタログと接合点.md`「法線方向のずらしは配置の決定である」

use blitz_math::メートル;

use super::error::接合点エラー;

#[derive(Debug, Clone, Copy, PartialEq)]
#[repr(transparent)]
pub struct 法線方向のずらし(メートル);

impl 法線方向のずらし {
    /// 非有限を型付きエラーで拒む。大きさを見ないのは、どこまで離してよいかを型が決めないためである。
    pub fn 生成する(量: メートル) -> Result<Self, 接合点エラー> {
        if 量.値().is_finite() {
            return Ok(Self(量));
        }
        Err(接合点エラー::法線方向のずらしが有限でない { 値: 量.値() })
    }

    /// 寄せない。面をぴったり向かい合わせる既定であり、積層の接合と、食い込ませない取付がこれを使う。
    pub fn 寄せない() -> Self {
        Self(メートル::生成する(0.0))
    }

    /// 食い込ませる量から作る。正の値を渡して負のずらしを得る口であり、
    /// 呼び出し側が負号を書き忘れて逆へ離す誤りを避ける。
    pub fn 食い込ませる量から生成する(量: メートル) -> Result<Self, 接合点エラー> {
        Self::生成する(メートル::生成する(-量.値()))
    }

    pub fn 値(self) -> メートル {
        self.0
    }
}
