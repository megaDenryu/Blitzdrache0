//! 接合の様式: 対になる2つの接合点について、何を検査すれば噛み合いが成立するかの区分。
//!
//! 様式が決めるのは噛み合いの判定の本質だけである。面が上下を向くか側面を向くかは接合点の宣言(向きと上方向)が持つ。
//! 一致と包含という名前は、その判定そのものを言う。
//!
//! 未定の枝を持つのは、実データが2つの様式のどちらにも当てはまらない種別を含むためである。屋根の棟と屋根の笠は、
//! 接合面が 0.2×6.2 と 6.8×2.6 であり、寸法の一致でも包含でも合格しない。黙って一致か包含のどちらかへ倒すと、
//! 寸法の検査が意味を持たないまま通る。**未定は「様式をまだ決めていない」であって「様式を持たない」ではない。**
//! 決めるのは、それを要求する部品が実物になったときである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合には2つの様式があり、検査すべきことが違う」

/// 包含の2つの側。どちらを名乗るかは種別で決まる。受け入れる大きい面が受け入れる側、占める小さいものが差し込む側である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 包含の役割 {
    受け入れる側,
    差し込む側,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 接合の様式 {
    /// 接合面の実寸が一致することを求める。面上の位置の自由度は無く、常に面の中心で噛み合う。
    一致,
    /// 受け入れる側の面が差し込む側の面を包含できることを求める。面上の位置は呼び出し側が指定する。
    /// 役割を様式へ埋め込むのは、「様式が包含なのにどちら側か決まっていない」という状態を型で消すためである。
    包含 { 役割: 包含の役割 },
    /// 何を検査すべきかがまだ決まっていない。この様式の種別で接合を組もうとしたら型付きエラーで拒む。
    未定,
}

impl 接合の様式 {
    pub fn 綴り(self) -> &'static str {
        match self {
            Self::一致 => "一致",
            Self::包含 { .. } => "包含",
            Self::未定 => "未定",
        }
    }
}
