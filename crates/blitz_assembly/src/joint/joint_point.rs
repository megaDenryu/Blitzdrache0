//! 接合点: 部品どうしを噛み合わせる1点。位置・姿勢・接合面の寸法を部品のローカル座標系で持つ。
//!
//! 生成が失敗しないのは、5つのフィールドがそれぞれ自分の不変条件を生成の時点で確かめてあるためである。
//! ここで再度検査すると、同じ規則の正本が2つになる。
//!
//! 位置を`位置<部品ローカル>`で持つのは、群のローカル空間(個体配置が住む場所)と取り違えないためである。
//! 同じ型にすると、接合点の位置をそのまま個体配置の平行移動へ渡す誤りが型で落ちない。

use blitz_math::{位置, 部品ローカル};

use super::face_pose::接合面の姿勢;
use super::face_size::接合面の形と寸法;
use super::joint_kind::接合種別;
use super::joint_name::接合点名;

#[derive(Debug, Clone, PartialEq)]
pub struct 接合点 {
    名前: 接合点名,
    種別: 接合種別,
    位置: 位置<部品ローカル>,
    姿勢: 接合面の姿勢,
    接合面: 接合面の形と寸法,
}

impl 接合点 {
    pub fn 生成する(
        名前: 接合点名, 種別: 接合種別, 位置: 位置<部品ローカル>, 姿勢: 接合面の姿勢, 接合面: 接合面の形と寸法
    ) -> Self {
        Self {
            名前,
            種別,
            位置,
            姿勢,
            接合面,
        }
    }

    pub fn 名前(&self) -> &接合点名 {
        &self.名前
    }

    pub fn 種別(&self) -> 接合種別 {
        self.種別
    }

    pub fn 位置(&self) -> 位置<部品ローカル> {
        self.位置
    }

    pub fn 姿勢(&self) -> 接合面の姿勢 {
        self.姿勢
    }

    pub fn 接合面(&self) -> 接合面の形と寸法 {
        self.接合面
    }
}
