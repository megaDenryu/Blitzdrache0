//! 接合種別: 接合点がどの噛み合わせに参加するかの区分。glTFのextrasが綴る日本語の文字列と1対1で対応する。
//!
//! どの種別とどの種別が対になるか、どの様式かは部品を横断する知識であり、種別そのものの定義とは変わる理由が違う。
//! そちらは`joint_kind_pairing`が持つ。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合種別と対応表」

use std::fmt;

use super::error::接合点エラー;

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum 接合種別 {
    上面積層,
    下面積層,
    壁面取付,
    壁面差込,
    屋根面取付,
    屋根面差込,
    屋根の棟,
    屋根の笠,
    壁のはめ口,
    壁の外枠,
    ベイの継ぎ口,
    扉の吊り元,
    扉板の吊り軸,
    幹頂部,
    幹基部,
    枝の生え口,
    枝の根元,
    頂芽,
    葉房の根元,
}

/// 全種別。被覆の報告が「どの種別が実データに現れていないか」を数えるために、種別の一覧をここが1箇所で持つ。
pub const 全接合種別: [接合種別; 19] = [
    接合種別::上面積層,
    接合種別::下面積層,
    接合種別::壁面取付,
    接合種別::壁面差込,
    接合種別::屋根面取付,
    接合種別::屋根面差込,
    接合種別::屋根の棟,
    接合種別::屋根の笠,
    接合種別::壁のはめ口,
    接合種別::壁の外枠,
    接合種別::ベイの継ぎ口,
    接合種別::扉の吊り元,
    接合種別::扉板の吊り軸,
    接合種別::幹頂部,
    接合種別::幹基部,
    接合種別::枝の生え口,
    接合種別::枝の根元,
    接合種別::頂芽,
    接合種別::葉房の根元,
];

impl 接合種別 {
    /// extrasが綴る文字列。列挙子の名前と同じ綴りにするのは、Blender側と本体側で別の対応表を持たないためである。
    pub fn 綴り(self) -> &'static str {
        match self {
            Self::上面積層 => "上面積層",
            Self::下面積層 => "下面積層",
            Self::壁面取付 => "壁面取付",
            Self::壁面差込 => "壁面差込",
            Self::屋根面取付 => "屋根面取付",
            Self::屋根面差込 => "屋根面差込",
            Self::屋根の棟 => "屋根の棟",
            Self::屋根の笠 => "屋根の笠",
            Self::壁のはめ口 => "壁のはめ口",
            Self::壁の外枠 => "壁の外枠",
            Self::ベイの継ぎ口 => "ベイの継ぎ口",
            Self::扉の吊り元 => "扉の吊り元",
            Self::扉板の吊り軸 => "扉板の吊り軸",
            Self::幹頂部 => "幹頂部",
            Self::幹基部 => "幹基部",
            Self::枝の生え口 => "枝の生え口",
            Self::枝の根元 => "枝の根元",
            Self::頂芽 => "頂芽",
            Self::葉房の根元 => "葉房の根元",
        }
    }

    /// 未知の綴りは型付きエラーで拒み、文字列のまま持ち回らない。綴りを誤った部品が黙って組み立てへ流れると、
    /// 対の相手が見つからない理由が「綴り違い」なのか「部品の不足」なのか読み手に分からなくなる。
    pub fn 綴りから読み取る(綴り: &str) -> Result<Self, 接合点エラー> {
        全接合種別
            .into_iter()
            .find(|種別| 種別.綴り() == 綴り)
            .ok_or_else(|| 接合点エラー::未知の接合種別 { 綴り: 綴り.to_string() })
    }
}

impl fmt::Display for 接合種別 {
    fn fmt(&self, 出力: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(出力, "{}", self.綴り())
    }
}
