//! 接合種別: 接合点がどの噛み合わせに参加するかの区分と、その全件の一覧。
//!
//! どの種別とどの種別が対になるか、どの様式かは部品を横断する知識であり、種別そのものの定義とは変わる理由が違う。
//! そちらは`joint_kind_pairing`と`joint_kind_style`が持つ。extrasが綴る文字列との対応は`joint_kind_spelling`が持つ。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合種別と対応表」

use std::fmt;

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum 接合種別 {
    上面積層,
    下面積層,
    壁面取付,
    壁面差込,
    屋根面取付,
    屋根面差込,
    屋根の棟,
    屋根の笠,
    壁のはめ口,
    壁の外枠,
    ベイの継ぎ口,
    床のはめ口,
    床の外枠,
    扉の吊り元,
    扉板の吊り軸,
    幹頂部,
    幹基部,
    枝の生え口,
    枝の根元,
    頂芽,
    葉房の根元,
}

