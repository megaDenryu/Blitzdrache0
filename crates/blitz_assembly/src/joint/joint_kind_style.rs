//! 接合種別への様式の割り当て。噛み合った2つで何を検査するかを持つ。誰と噛み合えるかは`joint_kind_pairing`が持つ。
//!
//! 対応表と分けているのは、変わる理由が違うためである。対応表は部品の種類が増えると増え、様式の割り当ては
//! 実データが様式を裏づけたときに未定から動く。種別を1つ足すと、この網羅的matchへ枝を書き足すまでコンパイルが通らない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合には2つの様式があり、検査すべきことが違う」

use super::joint_kind::接合種別;
use super::mating_style::{包含の役割, 接合の様式};

impl 接合種別 {
    /// 様式を割り当てるのは、何を検査すれば噛み合うかが実データで決まっている種別だけである。屋根の棟と屋根の笠は、
    /// 実データが2つの様式のどちらでも合格しないことが分かっているため未定のままにする。扉の吊り元と扉板の吊り軸は、
    /// 扉板の部品がまだ収蔵されておらず、蝶番の回転を接合面の姿勢だけで表せるかを実データで確かめていないため未定にする。
    /// **材料の無いまま様式を割り当てると、規則が実装の都合の写しになる。**
    ///
    /// 幹と枝と葉房の6種別を一致にするのは、実データの接合面がどれも円1つで宣言されており、太さがそろうことが
    /// 噛み合いの意味そのものだからである。幹頂部の直径0.4へ幹基部の直径0.5を継ぐと、子の倍率が0.8として導出される。
    ///
    /// 屋根面の対を包含にするのは、包含の検査(面の大小と面上の位置)が接合面の中の2次元の判定であり、
    /// その面が水平か垂直か傾いているかに依らないためである。傾きは接合面の姿勢が表しており、様式は関知しない。
    /// **屋根面を壁面と別の種別にするのは、語と実体を合わせるためである。** 屋根の傾斜面への取付を壁面差込と
    /// 名乗ると、1つの語が2つの実体を指すことになり、規則の読み手がどちらの面へ付くのかを名前から決められない。
    ///
    /// 壁のはめ口と壁の外枠の対を一致にするのは、骨格が宣言する枠 2.00×2.60 へ壁が同じ 2.00×2.60 で
    /// ぴったりはまる関係だからである。壁面の対の包含を流用すると、枠より小さい壁を差し込んでも合格し、
    /// 隙間の空いた組み上げが検査を素通りする。
    ///
    /// ベイの継ぎ口を一致にするのは、骨格どうしが同じ 2.00×2.60 の面をまるごと突き合わせるためである。
    /// 相互(対の相手が自分自身)であっても様式の決まり方は変わらない。面のどこかへ小さいものを付ける関係ではないため、
    /// 包含にすると隣のベイが面の一部だけで接する組み方が合格する。
    pub fn 様式(self) -> 接合の様式 {
        match self {
            Self::上面積層 | Self::下面積層 => 接合の様式::一致,
            Self::壁面取付 | Self::屋根面取付 => 接合の様式::包含 {
                役割: 包含の役割::受け入れる側,
            },
            Self::壁面差込 | Self::屋根面差込 => 接合の様式::包含 {
                役割: 包含の役割::差し込む側,
            },
            Self::屋根の棟 | Self::屋根の笠 => 接合の様式::未定,
            Self::壁のはめ口 | Self::壁の外枠 => 接合の様式::一致,
            Self::ベイの継ぎ口 => 接合の様式::一致,
            Self::扉の吊り元 | Self::扉板の吊り軸 => 接合の様式::未定,
            Self::幹頂部 | Self::幹基部 => 接合の様式::一致,
            Self::枝の生え口 | Self::枝の根元 => 接合の様式::一致,
            Self::頂芽 | Self::葉房の根元 => 接合の様式::一致,
        }
    }
}
