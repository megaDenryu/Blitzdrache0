//! 接合種別とglTFのextrasが綴る文字列の対応。綴りを答える工程と、綴りから種別を読み取る工程を持つ。
//!
//! 区分そのものの定義(`joint_kind`)から分けるのは、変わる理由が違うためである。区分は接合の語彙が増えると増え、
//! 綴りはBlender側と本体側が交わす契約の文字列であり、Blender側が名前を改めたときに変わる。
//! 対応表(`joint_kind_pairing`)と様式の割り当て(`joint_kind_style`)を種別の定義から分けているのと同じ分け方である。
//!
//! 列挙子の名前と同じ綴りにするのは、Blender側と本体側で別の対応表を持たないためである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合種別と対応表」

use super::error::接合点エラー;
use super::joint_kind::{全接合種別, 接合種別};

impl 接合種別 {
    /// extrasが綴る文字列。
    pub fn 綴り(self) -> &'static str {
        match self {
            Self::上面積層 => "上面積層",
            Self::下面積層 => "下面積層",
            Self::壁面取付 => "壁面取付",
            Self::壁面差込 => "壁面差込",
            Self::屋根面取付 => "屋根面取付",
            Self::屋根面差込 => "屋根面差込",
            Self::屋根の棟 => "屋根の棟",
            Self::屋根の笠 => "屋根の笠",
            Self::壁のはめ口 => "壁のはめ口",
            Self::壁の外枠 => "壁の外枠",
            Self::ベイの継ぎ口 => "ベイの継ぎ口",
            Self::床のはめ口 => "床のはめ口",
            Self::床の外枠 => "床の外枠",
            Self::扉の吊り元 => "扉の吊り元",
            Self::扉板の吊り軸 => "扉板の吊り軸",
            Self::幹頂部 => "幹頂部",
            Self::幹基部 => "幹基部",
            Self::枝の生え口 => "枝の生え口",
            Self::枝の根元 => "枝の根元",
            Self::頂芽 => "頂芽",
            Self::葉房の根元 => "葉房の根元",
        }
    }

    /// 未知の綴りは型付きエラーで拒み、文字列のまま持ち回らない。綴りを誤った部品が黙って組み立てへ流れると、
    /// 対の相手が見つからない理由が「綴り違い」なのか「部品の不足」なのか読み手に分からなくなる。
    pub fn 綴りから読み取る(綴り: &str) -> Result<Self, 接合点エラー> {
        全接合種別
            .into_iter()
            .find(|種別| 種別.綴り() == 綴り)
            .ok_or_else(|| 接合点エラー::未知の接合種別 { 綴り: 綴り.to_string() })
    }
}
