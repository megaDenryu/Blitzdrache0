//! 接合面上の位置: 包含のとき、親の接合面のどこへ子を付けるか。面の中心を原点とし、横は姿勢の横軸に、縦は姿勢の縦軸に沿う。
//!
//! この値を部品の側でなく呼び出し側が与えるのは、**部品の寸法から導出できない意匠の決定だから**である。
//! Blender側の建築の生成コードが`x_offset=1.5`(屋根のどこにドーマーを置くか)と書いていた数値がまさにこれである。
//!
//! 一致のときはこの型を渡す余地が無い。面の中心で一致するほかに置きようがないためである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合には2つの様式があり、検査すべきことが違う」

use blitz_math::メートル;

use super::error::接合点エラー;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接合面上の位置 {
    横: メートル,
    縦: メートル,
}

impl 接合面上の位置 {
    /// 非有限を型付きエラーで拒む。はみ出しの判定は接合を組む地点が行うため、ここでは大きさを見ない。
    pub fn 生成する(横: メートル, 縦: メートル) -> Result<Self, 接合点エラー> {
        有限かを確かめる("横", 横)?;
        有限かを確かめる("縦", 縦)?;
        Ok(Self { 横, 縦 })
    }

    /// 面の中心。一致の接合と、包含でずらさない場合がこれを使う。
    pub fn 中心() -> Self {
        Self {
            横: メートル::生成する(0.0),
            縦: メートル::生成する(0.0),
        }
    }

    pub fn 横(&self) -> メートル {
        self.横
    }

    pub fn 縦(&self) -> メートル {
        self.縦
    }
}

fn 有限かを確かめる(成分名: &'static str, 値: メートル) -> Result<(), 接合点エラー> {
    if 値.値().is_finite() {
        return Ok(());
    }
    Err(接合点エラー::接合面上の位置が有限でない { 成分名, 値: 値.値() })
}
