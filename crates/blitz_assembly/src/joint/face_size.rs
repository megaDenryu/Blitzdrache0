//! 接合面の形と寸法: 接合面が矩形か円かと、その面の寸法。
//!
//! 形を判別共用体で持つのは、噛み合いの判定が形ごとに違うためである。矩形は幅と高さの2つの長さで、
//! 円は直径1つで噛み合いが決まる。**円を「幅と高さが等しい矩形」で表すと、実物に無い組(矩形の面と円の面)が
//! 黙って通り、形ごとの判定の書き忘れも網羅matchが教えなくなる。**
//!
//! 幅は姿勢の横軸に、高さは姿勢の縦軸に沿う長さである。円の直径は面内のどの方向にも同じ長さである。
//!
//! 寸法を持つのは、位置だけ合って寸法の合わない接合が黙って通ることを防ぐためである。幅4メートルの壁の上へ
//! 幅3メートルの屋根を乗せても、寸法が無ければ機械は何も言わない。
//!
//! 寸法を持つことには副次の利点がある。部品の規格を1つに固定しなくてよい。幅2・3・4メートルの壁が共存でき、
//! 噛み合う組み合わせだけが成立する。規格を固定すると4メートル刻みの家しか建たない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合面の寸法を持つ理由」

use blitz_math::メートル;

use super::error::接合点エラー;
use super::positive_length::正で有限な長さ;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 接合面の形と寸法 {
    矩形 {
        幅: 正で有限な長さ,
        高さ: 正で有限な長さ,
    },
    円 {
        直径: 正で有限な長さ,
    },
}

impl 接合面の形と寸法 {
    pub fn 矩形を生成する(幅: メートル, 高さ: メートル) -> Result<Self, 接合点エラー> {
        Ok(Self::矩形 {
            幅: 正で有限な長さ::生成する("幅", 幅)?,
            高さ: 正で有限な長さ::生成する("高さ", 高さ)?,
        })
    }

    pub fn 円を生成する(直径: メートル) -> Result<Self, 接合点エラー> {
        Ok(Self::円 {
            直径: 正で有限な長さ::生成する("直径", 直径)?,
        })
    }
}
