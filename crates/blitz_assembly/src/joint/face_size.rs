//! 接合面寸法: 接合面の幅と高さ。幅は姿勢の横軸に、高さは姿勢の縦軸に沿う長さである。
//!
//! 寸法を持つのは、位置だけ合って寸法の合わない接合が黙って通ることを防ぐためである。幅4メートルの壁の上へ
//! 幅3メートルの屋根を乗せても、寸法が無ければ機械は何も言わない。
//!
//! 寸法を持つことには副次の利点がある。部品の規格を1つに固定しなくてよい。幅2・3・4メートルの壁が共存でき、
//! 噛み合う組み合わせだけが成立する。規格を固定すると4メートル刻みの家しか建たない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合面の寸法を持つ理由」

use blitz_math::メートル;

use super::error::接合点エラー;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接合面寸法 {
    幅: メートル,
    高さ: メートル,
}

impl 接合面寸法 {
    /// 零・負・非有限を型付きエラーで拒む。どれも噛み合いの判定が成り立たない値であり、
    /// 受け入れると「面が無い接合点」が組み立てへ流れる。
    pub fn 生成する(幅: メートル, 高さ: メートル) -> Result<Self, 接合点エラー> {
        正で有限かを確かめる("幅", 幅)?;
        正で有限かを確かめる("高さ", 高さ)?;
        Ok(Self { 幅, 高さ })
    }

    pub fn 幅(&self) -> メートル {
        self.幅
    }

    pub fn 高さ(&self) -> メートル {
        self.高さ
    }
}

fn 正で有限かを確かめる(辺名: &'static str, 長さ: メートル) -> Result<(), 接合点エラー> {
    let 値 = 長さ.値();
    if 値.is_finite() && 値 > 0.0 {
        return Ok(());
    }
    Err(接合点エラー::接合面の寸法が正で有限でない { 辺名, 値 })
}
