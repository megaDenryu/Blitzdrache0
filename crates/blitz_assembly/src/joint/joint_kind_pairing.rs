//! 接合種別の対応表と様式の割り当て。どの種別とどの種別が対になるか、対になった2つで何を検査するかを持つ。
//!
//! 種別の定義から分けているのは、これが部品を横断する知識であり、個々の部品のファイルには書けないものだからである。
//! 種別を1つ足すと、この2つの網羅的matchへ枝を書き足すまでコンパイルが通らない。文書に「対応表を更新すること」と
//! 書いても守られないが、これは守られる。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合種別と対応表」

use super::joint_kind::接合種別;
use super::mating_style::接合の様式;

impl 接合種別 {
    /// この種別と噛み合う相手の種別。対の関係は対称であり、2回適用すると元へ戻る。
    pub fn 対になる種別(self) -> Self {
        match self {
            Self::上面積層 => Self::下面積層,
            Self::下面積層 => Self::上面積層,
            Self::壁面取付 => Self::壁面差込,
            Self::壁面差込 => Self::壁面取付,
            Self::屋根の棟 => Self::屋根の笠,
            Self::屋根の笠 => Self::屋根の棟,
            Self::枝の生え口 => Self::枝の根元,
            Self::枝の根元 => Self::枝の生え口,
            Self::頂芽 => Self::葉房の根元,
            Self::葉房の根元 => Self::頂芽,
        }
    }

    /// 積層と取付を割り当てるのは、実データの部品がその様式で噛み合うことを確かめた4種別だけである。
    /// 残る6種別は未定にする。屋根の棟と屋根の笠は実データが2つの様式のどちらでも合格しないことが分かっており、
    /// 植物の4種別は部品が1件も無く、どちらの様式で噛み合うのかを確かめる材料が無い。
    /// **材料の無いまま様式を割り当てると、規則が実装の都合の写しになる。**
    pub fn 様式(self) -> 接合の様式 {
        match self {
            Self::上面積層 | Self::下面積層 => 接合の様式::積層,
            Self::壁面取付 | Self::壁面差込 => 接合の様式::取付,
            Self::屋根の棟 | Self::屋根の笠 => 接合の様式::未定,
            Self::枝の生え口 | Self::枝の根元 => 接合の様式::未定,
            Self::頂芽 | Self::葉房の根元 => 接合の様式::未定,
        }
    }
}
