//! 接合種別の対応表と様式の割り当て。どの種別とどの種別が対になるか、対になった2つで何を検査するかを持つ。
//!
//! 種別の定義から分けているのは、これが部品を横断する知識であり、個々の部品のファイルには書けないものだからである。
//! 種別を1つ足すと、この2つの網羅的matchへ枝を書き足すまでコンパイルが通らない。文書に「対応表を更新すること」と
//! 書いても守られないが、これは守られる。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合種別と対応表」

use super::joint_kind::接合種別;
use super::mating_style::{包含の役割, 接合の様式};

impl 接合種別 {
    /// この種別と噛み合う相手の種別。対の関係は対称であり、2回適用すると元へ戻る。
    pub fn 対になる種別(self) -> Self {
        match self {
            Self::上面積層 => Self::下面積層,
            Self::下面積層 => Self::上面積層,
            Self::壁面取付 => Self::壁面差込,
            Self::壁面差込 => Self::壁面取付,
            Self::屋根面取付 => Self::屋根面差込,
            Self::屋根面差込 => Self::屋根面取付,
            Self::屋根の棟 => Self::屋根の笠,
            Self::屋根の笠 => Self::屋根の棟,
            Self::枝の生え口 => Self::枝の根元,
            Self::枝の根元 => Self::枝の生え口,
            Self::頂芽 => Self::葉房の根元,
            Self::葉房の根元 => Self::頂芽,
        }
    }

    /// 一致と包含を割り当てるのは、何を検査すれば噛み合うかが決まっている6種別だけである。残る6種別は未定にする。
    /// 屋根の棟と屋根の笠は実データが2つの様式のどちらでも合格しないことが分かっており、植物の4種別は部品が1件も無く、
    /// どちらの様式で噛み合うのかを確かめる材料が無い。**材料の無いまま様式を割り当てると、規則が実装の都合の写しになる。**
    ///
    /// 屋根面の対を包含にするのは、包含の検査(面の大小と面上の位置)が接合面の中の2次元の判定であり、
    /// その面が水平か垂直か傾いているかに依らないためである。傾きは接合面の姿勢が表しており、様式は関知しない。
    /// **屋根面を壁面と別の種別にするのは、語と実体を合わせるためである。** 屋根の傾斜面への取付を壁面差込と
    /// 名乗ると、1つの語が2つの実体を指すことになり、規則の読み手がどちらの面へ付くのかを名前から決められない。
    pub fn 様式(self) -> 接合の様式 {
        match self {
            Self::上面積層 | Self::下面積層 => 接合の様式::一致,
            Self::壁面取付 | Self::屋根面取付 => 接合の様式::包含 {
                役割: 包含の役割::受け入れる側,
            },
            Self::壁面差込 | Self::屋根面差込 => 接合の様式::包含 {
                役割: 包含の役割::差し込む側,
            },
            Self::屋根の棟 | Self::屋根の笠 => 接合の様式::未定,
            Self::枝の生え口 | Self::枝の根元 => 接合の様式::未定,
            Self::頂芽 | Self::葉房の根元 => 接合の様式::未定,
        }
    }
}
