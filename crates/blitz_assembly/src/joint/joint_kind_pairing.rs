//! 接合種別の対応表。どの種別とどの種別が噛み合えるかを持つ。何を検査するかの割り当ては`joint_kind_style`が持つ。
//!
//! 種別の定義から分けているのは、これが部品を横断する知識であり、個々の部品のファイルには書けないものだからである。
//! 種別を1つ足すと、この網羅的matchへ枝を書き足すまでコンパイルが通らない。文書に「対応表を更新すること」と
//! 書いても守られないが、これは守られる。
//!
//! **相手が1つとは限らない。** 木では枝の根元が幹頂部と枝の生え口と頂芽の3つへ付き、頂芽は枝の根元と葉房の根元の
//! 2つを受ける。1対1の表では、同じ部品を幹の先にも枝の先にも継げる木を表せない。対称性(相手の一覧に自分が入ること)は
//! 単体試験が固定する。
//!
//! **相手が自分自身である種別を相互と呼ぶ。** ベイの継ぎ口がそれであり、骨格の右面の継ぎ口へ隣の骨格の左面の継ぎ口が
//! 噛み合う。取り付ける側と取り付けられる側の区別が無いため、対の相手を別の種別として立てると、
//! どちらを名乗るかの判断が部品ごとに要る。相互の載せ忘れはこの網羅的matchが防ぐ。枝を書き足すまでコンパイルが通らない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合種別と対応表」「役割「相互」」

use super::joint_kind::接合種別;

impl 接合種別 {
    /// この種別と噛み合える相手の種別。宣言の順が、破れの文面へ並ぶ順になる。
    pub fn 噛み合う相手の種別一覧(self) -> &'static [接合種別] {
        match self {
            Self::上面積層 => &[Self::下面積層],
            Self::下面積層 => &[Self::上面積層],
            Self::壁面取付 => &[Self::壁面差込],
            Self::壁面差込 => &[Self::壁面取付],
            Self::屋根面取付 => &[Self::屋根面差込],
            Self::屋根面差込 => &[Self::屋根面取付],
            Self::屋根の棟 => &[Self::屋根の笠],
            Self::屋根の笠 => &[Self::屋根の棟],
            Self::壁のはめ口 => &[Self::壁の外枠],
            Self::壁の外枠 => &[Self::壁のはめ口],
            Self::ベイの継ぎ口 => &[Self::ベイの継ぎ口],
            Self::扉の吊り元 => &[Self::扉板の吊り軸],
            Self::扉板の吊り軸 => &[Self::扉の吊り元],
            Self::幹頂部 => &[Self::幹基部, Self::枝の根元],
            Self::幹基部 => &[Self::幹頂部],
            Self::枝の生え口 => &[Self::枝の根元],
            Self::枝の根元 => &[Self::幹頂部, Self::枝の生え口, Self::頂芽],
            Self::頂芽 => &[Self::枝の根元, Self::葉房の根元],
            Self::葉房の根元 => &[Self::頂芽],
        }
    }

    pub fn 噛み合うか(self, 相手: Self) -> bool {
        self.噛み合う相手の種別一覧().contains(&相手)
    }

    /// 破れの文面へ載せる、噛み合える相手の綴り。読み手が「どの種別を宣言すべきか」を決めるために要る。
    pub fn 噛み合う相手の綴り(self) -> String {
        self.噛み合う相手の種別一覧()
            .iter()
            .map(|種別| 種別.綴り())
            .collect::<Vec<&str>>()
            .join("か")
    }
}
