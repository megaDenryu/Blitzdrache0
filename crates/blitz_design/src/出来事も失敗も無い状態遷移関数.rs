//! 出来事を出さず失敗もしない状態遷移の3つの役割(`M状態遷移が受け取る命令で決まる状態遷移関数`・`M規則で決まる状態遷移関数`・`M規則と状態遷移パラメータで決まる状態遷移関数`)。
//!
//! `M状態遷移関数` の形(規則と状態遷移パラメータを受け、`Result<状態遷移成功結果, 状態遷移失敗結果>` を返す)へ、規則を読まない状態遷移や
//! 出来事を出さない状態遷移を押し込むと、意味を持たない型(読まない規則・受けないパラメータ・起こりえない出来事)を関数の署名と
//! 設計関係グラフへ持ち込み、呼び出し側は起こりえない失敗を毎回ほどくことになる。そこで、次の状態がどの入力だけで決まるかを
//! 役割の名前で言い、関数は次の状態をそのまま返す。どちらも出来事を出さず、失敗しない。
//! 出来事を出す状態遷移・失敗しうる状態遷移は `M状態遷移関数` で宣言する。コマンドを受けずに規則と状態遷移パラメータだけを受け、出来事を出さず失敗しない状態遷移は
//! `M規則と状態遷移パラメータで決まる状態遷移関数` で宣言する(例は目的地への到達の判定であり、道順が規則、プレイヤーの位置が状態遷移パラメータである)。
//! 参照: `_doc/設計/設計オントロジー.md` 第3節。

use crate::設計解釈マーカー::{MParameter, M状態, M状態遷移が受け取る命令, M規則};

/// 次の状態が、今の状態と状態遷移が受け取る命令(`Mコマンド` か `M命令の組`)だけで決まる状態遷移。規則を読まず、出来事を出さず、失敗しない。状態は値で受け取り、コマンドは参照で読む。
/// コマンドの位置は `Mコマンド` も `M命令の組` も受け取る(境界は両者の上位の `M状態遷移が受け取る命令`)。
#[derive(Clone, Copy)]
pub struct M状態遷移が受け取る命令で決まる状態遷移関数<状態: M状態, コマンド: M状態遷移が受け取る命令>(fn(状態, &コマンド) -> 状態);

impl<状態: M状態, コマンド: M状態遷移が受け取る命令> M状態遷移が受け取る命令で決まる状態遷移関数<状態, コマンド> {
    /// 関数を状態遷移が受け取る命令で決まる状態遷移の役割で包む。
    pub const fn 生成する(関数: fn(状態, &コマンド) -> 状態) -> Self {
        Self(関数)
    }

    /// 包んだ関数へ状態とコマンドを渡し、次の状態を得る。
    pub fn 呼び出す(&self, 状態: 状態, コマンド: &コマンド) -> 状態 {
        (self.0)(状態, コマンド)
    }
}

