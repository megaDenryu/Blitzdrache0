//! 設計マーカー。型が設計上どの役割として解釈されるかを、メソッドを持たないトレイトの実装で宣言する。
//!
//! `Clone` を上位トレイトに置くことでコンパイラが保証するのは複製できることだけである。参照・生ポインタ・内部可変性を持たないことは
//! `cargo xtask conform` の設計オントロジーの検査が `MDTO` を実装する型に対して見る。
//! データの役割(`M状態`・`Mコマンド`・`Mイベント`・`M規則`・`M入力`・`M設定`)はすべて `MDTO` を上位トレイトに持ち、純粋な所有データであることの宣言を含む。
//! `MDTO` は境界を越える転送にも状態の正本にも使う。
//! 参照: `_doc/計画/ユビキタス言語.md`「設計マーカー」、`_doc/設計/設計オントロジー.md`。

/// 設計上の役割: 参照や内部可変性を所有せず、値として複製・受け渡しできる純粋な所有データ。境界を越える転送にも状態の正本にも使う。
pub trait MDTO: Clone {}

/// 設計上の役割: 純粋な所有データであり、実在し、保持され、遷移されるゲームまたはシミュレーションの状態。
pub trait M状態: MDTO {}

/// 設計上の役割: 純粋な所有データであり、主体が選択・発行する命令、意図。必ず選択肢を数え上げた列挙で表し、固有の `impl` に `&mut self` を持たない。
pub trait Mコマンド: MDTO {}

/// 設計上の役割: 純粋な所有データであり、ある状態遷移によって成立した過去の事実。固有の `impl` に `&mut self` を持たない。
pub trait Mイベント: MDTO {}

/// 設計上の役割: 純粋な所有データであり、計算や遷移を律する不変の法則、方針。必ず構造体で表し、固有の `impl` に `&mut self` を持たない。
pub trait M規則: MDTO {}

/// 設計上の役割: 純粋な所有データであり、外界(入力デバイス等)から届く、意味付けの前の生の信号。
pub trait M入力: MDTO {}

/// 設計上の役割: 純粋な所有データであり、起動時に決まって実行の間は変わらない設定。固有の `impl` に `&mut self` を持たない。
pub trait M設定: MDTO {}

/// 設計上の役割: 状態を読み書きして進める工程。
pub trait M工程 {}
