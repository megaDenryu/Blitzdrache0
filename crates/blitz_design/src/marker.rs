//! 設計解釈マーカーとは、型が設計上どの役割として解釈されるかを、メソッドを持たないトレイトの実装で宣言する印のことである。
//!
//! `Clone` を上位トレイトに置くことでコンパイラが保証するのは複製できることだけである。参照・生ポインタ・内部可変性を持たないことと、
//! 固有の `impl` とトレイトの実装に `&mut self` を持たないことは `cargo xtask conform` の設計オントロジーの検査が `M不変データ` を実装する型に対して見る。
//! データの役割(`M状態`・`Mコマンド`・`Mイベント`・`M規則`・`M入力`・`M観測`)はすべて `M不変データ` を上位トレイトに持ち、純粋な所有データであることの宣言を含む。
//! `M不変データ` は、境界を越える転送にも状態の正本にも使われる型である。
//! マーカーは互いに直交する5つの軸を持つ。データの役割(`M状態`・`Mコマンド`・`Mイベント`・`M規則`・`M入力`・`M観測`。因果モデルのどこに現れるか。`M不変データ` はその一種でなく、複数のデータの役割が共有する基底の契約である)、
//! 処理の役割(`M工程`。データではなく処理である)、存在の分類(`M値オブジェクト`・`Mエンティティ`・`Mエンティティ識別子`。同一性を持つか)、変更可能性(`M不変エンティティ`・`M可変エンティティ`。自己変更を行うか)、
//! 関数境界の役割(`MParameter`・`MOptions`・`M結果`。関数の境界をどう渡るか)である(2026-09-20 のオーナー裁定)。
//! 「マーカーはメソッドを持たない」の例外は `Mエンティティ` だけである。変更可能性の2つと関数境界の役割のうち `MParameter` と `MOptions` はそれぞれ排他であり、同じ型が両方を名乗ることは `cargo xtask conform` が違反にする。
//! 参照: `_doc/計画/ユビキタス言語.md`「M状態はM不変データである」「存在の分類」、`_doc/設計/設計オントロジー.md` 第2節・2.5節・2.6節。

use std::hash::Hash;

/// 設計上の役割: 参照や内部可変性を所有せず、値として複製・受け渡しできる純粋な所有データ。境界を越える転送にも状態の正本にも使われる型である。
/// 2026-09-20 のオーナー裁定による意味は次の5つである。内部可変性を持たない。自己変更を行わない(固有の `impl` とトレイトの実装に `&mut self` を持たない)。値として複製・受け渡しできる。
/// 変更が必要な場合は既存の値を書き換えるのではなく新しい値を構築する。変数への再代入や別の値への置き換えそのものは禁止しない。
pub trait M不変データ: Clone {}

/// 設計上の役割: 純粋な所有データであり、実在し、保持され、遷移されるゲームまたはシミュレーションの状態。遷移は新しい状態を返す工程が担い、状態自身は `&mut self` を持たない。
pub trait M状態: M不変データ {}

/// 設計上の役割: 純粋な所有データであり、主体が選択・発行する命令、意図。必ず選択肢を数え上げた列挙で表す。
pub trait Mコマンド: M不変データ {}

/// 設計上の役割: 純粋な所有データであり、ある状態遷移によって成立した過去の事実。
pub trait Mイベント: M不変データ {}

/// 設計上の役割: 純粋な所有データであり、遷移からは読み取り専用で与えられる規則値(内部可変性を持たず、型自身に可変メソッドを持たない。値の置き換えを型では禁じない)。必ず構造体で表す。
pub trait M規則: M不変データ {}

/// 設計上の役割: 純粋な所有データであり、外界(入力デバイス等)から届く、意味付けの前の生の信号。
pub trait M入力: M不変データ {}

/// 設計上の役割: 純粋な所有データであり、状態・処理・評価について、正本や因果を構成せず、計器や開発用の画面などが観察するために導出されたデータ。法則は5つである(2026-09-20 のオーナー裁定)。
/// 正本ではない。観測の対象そのものの因果へ戻さない。`struct` と `enum` のどちらであるかは本質ではない。`Mイベント`(ドメイン上で成立した過去の事実)とは別の概念であり、`M観測` は対象を外から見るために導出した情報である。`M結果` の部分型にはしない。
pub trait M観測: M不変データ {}

/// 設計上の役割: 状態を読み書きして進める工程。
pub trait M工程 {}

/// 関数境界の役割: 関数の実行に必要な必須入力を、名前付きのプロパティとして1つの引数オブジェクトへ束ねた型。法則は4つである。関数へ渡す必須入力の束である。
/// 各プロパティは必要だから存在する値である。`Option<T>` をフィールドとして持たない(`cargo xtask conform` が検査する)。不変性は `M不変データ` から継承する。
/// 値が無い状態がドメイン上の必須入力なら、`Option<T>` を置かずにその意味を表す専用の型か列挙へ持ち上げる(2026-09-20 のオーナー裁定)。
pub trait MParameter: M不変データ {}

/// 関数境界の役割: 関数呼び出し時に、呼び出し側が任意に指定できる設定を束ねる引数オブジェクト。法則は4つである。`Option<T>` をフィールドとして持つことを許す。
/// 全フィールドが `Option<T>` である必要は無い。`Option<T>` を持つこと自体は成立の条件でない。指定してもしなくても関数の呼び出しが成立する設定を束ねる(2026-09-20 のオーナー裁定)。
pub trait MOptions: M不変データ {}

/// 関数境界の役割: ある評価が取り得る排他的な帰結を表す判別型。`Result<T, E>` が代表例であり、3つ以上の選択肢を持つドメイン固有の列挙でもよい。
/// 本質は `Result` という標準の型そのものではなく、排他的な帰結を持つ判別型であることにある。各選択肢が運ぶ値(`遷移成功結果`・`遷移失敗結果`)そのものは `M結果` ではない(2026-09-20 のオーナー裁定)。
/// 上位トレイトを付けないのは、`Result<T, E>` の性質が `T` と `E` に依存し、一律に `M不変データ` を課せないためである。
pub trait M結果 {}

// 標準の `Result` は成功と失敗の2つの排他的な帰結を表す判別型であり、そのまま `M結果` である。
impl<T, E> M結果 for Result<T, E> {}

/// 存在の分類: 同一性を持たず、その値そのものによって意味と等価性が決まる型。法則は3つである。自己同一性を持たない。内容が同じなら同じ値として扱う。自己変更せず、変更は新しい値の生成として表す(`M不変データ` から継承する)。
/// 基底を `Eq` でなく `PartialEq` にするのは、`f32` を含む値オブジェクトでは完全な同値(反射律)が成り立たないことがあるためである。`Eq` が成り立つ値オブジェクトと成り立たない値オブジェクトを将来分けてよい。
pub trait M値オブジェクト: M不変データ + PartialEq {}

/// 存在の分類: ライフサイクルを通して維持される同一性を持ち、状態が変化しても同じものとして追跡される型。同一性は全フィールドの一致ではなく識別子の一致で決まるため、`PartialEq` を要求しない。
/// 設計解釈マーカーの中でこれだけがメソッドを持つ。どの値がそのエンティティの識別子なのかを機械的に取得できるようにするためである(2026-09-20 のオーナー裁定)。
pub trait Mエンティティ {
    /// このエンティティを同定する識別子の型。値オブジェクトとして扱う。
    type 識別子: Mエンティティ識別子;

    /// このエンティティの識別子。
    fn 識別子(&self) -> &Self::識別子;
}

/// 存在の分類: エンティティの同一性を担う識別子。値オブジェクトとして扱い、同定に使えるよう完全な同値(`Eq`)とハッシュ(`Hash`)を要求する。
pub trait Mエンティティ識別子: M値オブジェクト + Eq + Hash {}

/// 変更可能性: 同一性とライフサイクルを持つこと(`Mエンティティ`)と自己変更を禁じること(`M不変データ`)の合成。新しい哲学ではなく、2つの既存の概念の合成である。
pub trait M不変エンティティ: Mエンティティ + M不変データ {}

/// 変更可能性: 同一性を維持したまま内部の状態を更新する設計を意図していることを示す分類の印。`M不変エンティティ` と排他である。強い追加の法則を持たない。
pub trait M可変エンティティ: Mエンティティ {}
