//! 設計マーカー。型が設計上どの役割として解釈されるかを、メソッドを持たないトレイトの実装で宣言する。
//!
//! `Clone` を上位トレイトに置いたマーカーは、参照を持たず値として運べることをコンパイラに確かめさせる。
//! `M状態: MDTO` と `M入力: MDTO` は、状態と入力が境界を越えるデータであることの宣言である。
//! 参照: `_doc/計画/ユビキタス言語.md`「設計マーカー」。

/// 設計上の役割: 境界を越えて運ばれる純粋なデータ。参照・ポインタ・内部可変性を持たず、複製できる。
pub trait MDTO: Clone {}

/// 設計上の役割: 実在し、保持され、遷移されるゲームまたはシミュレーションの状態。状態は境界を越えるデータでもある。
pub trait M状態: MDTO {}

/// 設計上の役割: 主体が選択・発行する命令、意図。必ず選択肢を数え上げた列挙で表す。
pub trait Mコマンド {}

/// 設計上の役割: ある瞬間に生じた一過性の出来事、過去の事実。複製できる。
pub trait Mイベント: Clone {}

/// 設計上の役割: 計算や遷移を律する不変の法則、方針。必ず構造体で表す。
pub trait M規則 {}

/// 設計上の役割: 外界(入力デバイス等)から届く、意味付けの前の生の信号。境界を越えるデータでもある。
pub trait M入力: MDTO {}

/// 設計上の役割: 起動時に決まって実行の間は変わらない設定。
pub trait M設定 {}

/// 設計上の役割: 状態を読み書きして進める工程。
pub trait M工程 {}
