//! 遷移関数の役割(`M遷移関数`)と、その戻り値の形を固定する2つの意味型(`遷移成功結果`・`遷移失敗結果`)。
//!
//! 遷移関数とは、状態とコマンドと規則と遷移パラメータから、次の状態とその遷移で成立した出来事を導く純粋計算のことである。
//! 遷移は状態を値で受け取る(所有権を移す)。古い状態を参照で読んで新しい状態を組み直す形にすると、1か所しか変わらない遷移でも
//! 状態の大きさに比例した複製が毎回かかるためである(2026-09-26 のオーナー裁定)。所有権を受け取って新しい値を返すことは自己変更ではない。
//! 遷移は失敗しうるため、戻り値は `Result<遷移成功結果, 遷移失敗結果>` である。失敗のときは受け取った状態を `遷移失敗結果` に入れて
//! そのまま返し、呼び出し側は元の状態を維持する。失敗しない遷移は失敗の型に `std::convert::Infallible` を置く。
//!
//! 遷移パラメータを型引数にするのは、状態でもコマンドでも規則でもない必須の入力(経過時間・刻みの始まりの時刻など)がドメインごとに違うためである。
//! 2026-09-27 のオーナー裁定(Issue #175)で、Esca が固定していた `遷移パラメータ` を型引数へ一般化してこのクレートへ移した。
//! 型引数の境界は構造体の宣言に書き、利用箇所でコンパイラが強制する(型エイリアスの境界は強制されない。rust-lang/rust#112792)。
//! 規則を読まない遷移・出来事を出さない遷移・失敗しない遷移のために、形を縮めた役割を別に置く(`出来事も失敗も無い遷移関数.rs`)。
//! 参照: `_doc/設計/設計オントロジー.md` 第3節・3.5.1・3.5.9。

use crate::設計解釈マーカー::{MParameter, Mイベント, M状態, M規則, M遷移が受け取る命令};

/// 遷移関数が返す、次の状態と、その遷移で生じた出来事の一覧の組。生のタプルで返さないための名前付きの結果であり、
/// 型引数に `M状態`・`Mイベント` の境界を持つ意味型である。境界は構造体の利用箇所でコンパイラが強制する。
#[derive(Debug, Clone, PartialEq)]
pub struct 遷移成功結果<状態: M状態, イベント: Mイベント> {
    /// 遷移した後の状態。
    pub 次の状態: 状態,
    /// その遷移で成立した事実の一覧。
    pub 出来事一覧: Vec<イベント>,
}

/// 遷移関数が失敗のときに返す、受け取った状態と具体の失敗の組。遷移は状態を値で受け取るため、失敗のときはこの値の中で状態を呼び出し側へ返す。
/// 型引数に `M状態`・`std::error::Error` の境界を持つ意味型である。出来事は持たない(失敗した遷移では事実が成立していないため)。
/// 返す値が受け取った値と等しいことは型では保証されず、有限全数の検証が確かめる(設計オントロジー 3.5.9)。
#[derive(Debug, Clone, PartialEq)]
pub struct 遷移失敗結果<状態: M状態, 失敗: std::error::Error> {
    /// 遷移が受け取り、書き換えずに返す状態。
    pub 元の状態: 状態,
    /// 有効な次の状態を構築できなかった理由。
    pub 失敗の理由: 失敗,
}

/// (状態, コマンド, 規則, 遷移パラメータ) から次の状態と出来事を導く純粋計算。状態は値で受け取り、コマンドと規則は参照で読み、遷移パラメータは値で受け取る。
/// コマンドの位置は、1つの選択(`Mコマンド`)も、同じ刻みに届いた命令の全体(`M命令の組`)も受け取る(境界は両者の上位の `M遷移が受け取る命令`)。
#[derive(Clone, Copy)]
pub struct M遷移関数<状態: M状態, コマンド: M遷移が受け取る命令, 規則: M規則, パラメータ: MParameter, イベント: Mイベント, 失敗: std::error::Error>(
    遷移の関数ポインタ<状態, コマンド, 規則, パラメータ, イベント, 失敗>,
);

/// `M遷移関数` が包む関数ポインタの型。境界は `M遷移関数` の宣言が持ち、この別名は型の書き方を1箇所にまとめるだけである。
pub type 遷移の関数ポインタ<状態, コマンド, 規則, パラメータ, イベント, 失敗> = fn(状態, &コマンド, &規則, パラメータ) -> Result<遷移成功結果<状態, イベント>, 遷移失敗結果<状態, 失敗>>;

impl<状態: M状態, コマンド: M遷移が受け取る命令, 規則: M規則, パラメータ: MParameter, イベント: Mイベント, 失敗: std::error::Error> M遷移関数<状態, コマンド, 規則, パラメータ, イベント, 失敗> {
    /// 関数を遷移の役割で包む。
    pub const fn 生成する(関数: 遷移の関数ポインタ<状態, コマンド, 規則, パラメータ, イベント, 失敗>) -> Self {
        Self(関数)
    }

    /// 包んだ関数へ状態を渡し、コマンド・規則・遷移パラメータとともに適用して、遷移成功結果か遷移失敗結果を得る。
    pub fn 呼び出す(&self, 状態: 状態, コマンド: &コマンド, 規則: &規則, パラメータ: パラメータ) -> Result<遷移成功結果<状態, イベント>, 遷移失敗結果<状態, 失敗>> {
        (self.0)(状態, コマンド, 規則, パラメータ)
    }
}
