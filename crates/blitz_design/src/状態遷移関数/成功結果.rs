//! 状態遷移の成功側の値。次の状態と出来事一覧を所有し、一覧の入れ物は状態遷移ごとに選ぶ。

use crate::設計解釈マーカー::{Mイベント, M状態};

/// 状態遷移関数が返す、次の状態と、その状態遷移で生じた出来事の一覧の組。生のタプルで返さないための名前付きの結果であり、
/// 一覧の型は状態遷移ごとに選び、読み出しはイベントのスライスに統一する。既定は `Vec` である。
#[derive(Debug, Clone, PartialEq)]
pub struct 状態遷移成功結果<状態: M状態, イベント: Mイベント, 一覧: AsRef<[イベント]> = Vec<イベント>> {
    次の状態: 状態,
    出来事一覧: 一覧, // その状態遷移で成立した事実の一覧
    イベントの型: std::marker::PhantomData<イベント>,
}

impl<状態: M状態, イベント: Mイベント, 一覧: AsRef<[イベント]>> 状態遷移成功結果<状態, イベント, 一覧> {
    /// 状態遷移した後の状態と、その状態遷移で成立した事実の一覧から成功結果を作る。
    pub fn 生成する(次の状態: 状態, 出来事一覧: 一覧) -> Self {
        Self {
            次の状態,
            出来事一覧,
            イベントの型: std::marker::PhantomData,
        }
    }

    /// 状態遷移した後の状態を読む。
    pub fn 次の状態(&self) -> &状態 {
        &self.次の状態
    }

    /// その状態遷移で成立した事実の一覧を読む。
    pub fn 出来事一覧(&self) -> &[イベント] {
        self.出来事一覧.as_ref()
    }

    /// 出来事一覧を捨て、状態遷移した後の状態だけを所有権ごと取り出す。
    pub fn 次の状態を取り出す(self) -> 状態 {
        self.次の状態
    }

    /// 状態遷移した後の状態と出来事一覧を、所有権ごと2つへ分ける。
    pub fn 次の状態と出来事一覧へ分ける(self) -> (状態, 一覧) {
        (self.次の状態, self.出来事一覧)
    }
}

