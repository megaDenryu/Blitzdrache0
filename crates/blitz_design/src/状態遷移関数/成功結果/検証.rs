use super::状態遷移成功結果;
#[path = "検証/素材.rs"]
mod 素材;
use 素材::{検証用の出来事, 検証用の命令, 検証用の状態, 検証用の状態遷移パラメータ, 検証用の規則};

#[test]
fn 固定長配列の出来事を順序と所有権を保って返す() {
    let 出来事 = [検証用の出来事::開始した, 検証用の出来事::終了した];
    let 結果 = 状態遷移成功結果::生成する(検証用の状態, 出来事.clone());
    assert_eq!(結果.次の状態(), &検証用の状態);
    assert_eq!(結果.出来事一覧(), &出来事);
    let (状態, 取り出した出来事) = 結果.次の状態と出来事一覧へ分ける();
    assert_eq!(状態, 検証用の状態);
    assert_eq!(取り出した出来事, 出来事);
}

#[test]
fn 空の固定長配列を出来事のない成功結果として返す() {
    let 結果 = 状態遷移成功結果::<_, 検証用の出来事, _>::生成する(検証用の状態, []);
    assert!(結果.出来事一覧().is_empty());
    assert_eq!(結果.次の状態を取り出す(), 検証用の状態);
}

#[test]
fn 一覧の型を省略した成功結果は従来どおり可変長一覧を返す() {
    let 結果: 状態遷移成功結果<検証用の状態, 検証用の出来事> = 状態遷移成功結果::生成する(検証用の状態, vec![検証用の出来事::開始した]);
    assert_eq!(結果.出来事一覧(), &[検証用の出来事::開始した]);
}

#[test]
fn 関数の役割も固定長配列の出来事を返す状態遷移を包める() {
    let 関数 = crate::M状態遷移関数::生成する(検証用の状態::配列の出来事を返す);
    let 結果 = match 関数.呼び出す(検証用の状態, &検証用の命令::進める, &検証用の規則, 検証用の状態遷移パラメータ) {
        Ok(結果) => 結果,
        Err(失敗) => 失敗.起こらない失敗の分岐を閉じる(),
    };
    assert_eq!(結果.出来事一覧(), &[検証用の出来事::開始した]);
}
