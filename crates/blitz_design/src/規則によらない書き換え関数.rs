//! ゲームの規則を通さずに状態の一部を外から書き換える関数の役割(`M規則によらない書き換え関数`)。
//!
//! 遷移の役割はどれも、ゲームの規則(コマンド・規則・遷移パラメータ)に従って状態を次の状態へ進める。この役割はそれと違い、
//! シミュレーションの外から来た材料(地形のデータを差し替えたときの地面の高さなど)で、状態の一部を外から合わせる。
//! 遷移と別の役割に分けるのは、規則によらない書き換えが状態の存在理由(規則で進むこと)にならないためである。定義の式はこの役割から、
//! 状態を `書き換える` 関係と材料を `変換用の素材にする` 関係を導き、状態を `変換用の素材にする`・`生成する` 関係を導かない(`_doc/設計/設計オントロジー.md` 第3節・6.5節)。
//!
//! 材料の型に設計解釈マーカーの境界を置かないのは、材料がシミュレーションの外から来る値であり、単位の型(`blitz_math` の `大域メートル` など)のように、
//! 設計語彙のクレートに依存しないクレートの型で運ばれることがあるためである。その型には孤児規則のためにマーカーを実装できない。

use crate::設計解釈マーカー::M状態;

/// ゲームの規則を通さずに、材料で状態の一部を外から書き換える関数。状態も材料も値で受け取り、書き換えた状態を返す。出来事を出さず、失敗しない。
#[derive(Clone, Copy)]
pub struct M規則によらない書き換え関数<状態: M状態, 材料>(fn(状態, 材料) -> 状態);

impl<状態: M状態, 材料> M規則によらない書き換え関数<状態, 材料> {
    /// 関数を規則によらない書き換えの役割で包む。
    pub const fn 生成する(関数: fn(状態, 材料) -> 状態) -> Self {
        Self(関数)
    }

    /// 包んだ関数へ状態と材料を渡し、書き換えた状態を得る。
    pub fn 呼び出す(&self, 状態: 状態, 材料: 材料) -> 状態 {
        (self.0)(状態, 材料)
    }
}
