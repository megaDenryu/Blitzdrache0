//! 共通設計語彙。Rust上の型が設計上何として解釈されるか(状態・コマンド・イベント・規則・入力・設定・工程)を
//! 宣言するためのマーカーと、射影・解釈という関数の役割を表す境界付きの newtype だけを持つ。
//!
//! このクレートはドメインの語彙を1つも持たない。判定の基準は「その型が何について語るか」である。
//! プログラムについて語る(型が設計上どの役割かを言う)ものは `blitz_design` に置く。
//! シミュレーションについて語る(時間尺度・物理小刻み等)ものは `blitz_sim` に置く。
//! Esca世界について語る(旅行者・移動可能範囲等)ものは `blitz_esca` に置く。
//!
//! 注意: このクレートは何にも依存しない最下層である。依存の向きは `xtask/src/conform/dependency_whitelist/ledger.rs` の
//! 白リストが機械で強制する。マーカーが課す法則のうち、`MDTO` の `Clone` と、各役割(`M状態`・`Mコマンド`・`Mイベント`・`M規則`・`M入力`・`M設定`)の
//! `MDTO` 実装と、関数の役割の型引数の境界(境界付きの newtype であり、型を使った時点でコンパイラが強制する。迂回できる綴りは無い)はコンパイラが強制し、
//! 残りの法則は `cargo xtask conform` の設計オントロジーの検査が見る。
//! 参照: `_doc/設計/設計オントロジー.md`。

#![forbid(unsafe_code)]
#![warn(missing_docs)]

mod function_role;
mod marker;

pub use function_role::{M射影関数, M解釈関数};
pub use marker::{MDTO, Mイベント, Mコマンド, M入力, M工程, M状態, M規則, M設定};
