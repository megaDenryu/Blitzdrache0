//! 共通設計語彙。Rust上の型が設計上何として解釈されるか(データの役割: 状態・コマンド・イベント・規則・解釈前の入力(生入力と中間入力)・観測。処理の役割: 工程。存在の分類: 値オブジェクト・エンティティ・
//! エンティティ識別子。変更可能性: 不変エンティティ・可変エンティティ。関数境界の役割: 必須入力の束と任意の設定の束と評価の排他的な帰結)を宣言するためのマーカーと、射影・解釈という関数の役割を表す境界付きの newtype だけを持つ。
//!
//! このクレートはドメインの語彙を1つも持たない。判定の基準は「その型が何について語るか」である。
//! プログラムについて語る(型が設計上どの役割かを言う)ものは `blitz_design` に置く。
//! シミュレーションについて語る(時間尺度・物理小刻み等)ものは `blitz_sim` に置く。
//! Esca世界について語る(旅行者・移動可能範囲等)ものは `blitz_esca` に置く。
//!
//! 注意: このクレートは何にも依存しない最下層である。依存の向きは `xtask/src/conform/dependency_whitelist/ledger.rs` の
//! 白リストが機械で強制する。マーカーが課す法則のうち、`M不変データ` の `Clone` と、各役割(`M状態`・`Mコマンド`・`Mイベント`・`M規則`・`M解釈前の入力`・`M生入力`・`M中間入力`・`M観測`)の
//! `M不変データ` 実装と、関数の役割の型引数の境界(境界付きの newtype であり、型を使った時点でコンパイラが強制する。迂回できる書き方は無い)はコンパイラが強制し、
//! 残りの法則は `cargo xtask conform` の設計オントロジーの検査が見る。
//! 参照: `_doc/設計/設計オントロジー.md`。

