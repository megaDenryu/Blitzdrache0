//! 関数の設計上の役割を表す関数型と、その型引数が設計マーカーを満たすことをコンパイラに確かめさせる恒等の関数。
//!
//! 型エイリアスに書いた境界は強制されない(rust-lang/rust#112792)。そのため境界を恒等の `const fn` の
//! 型引数へ置き、利用側が `const _: M射影関数<A, B> = 射影関数として確認する(関数);` と書くことで、
//! 型引数が役割を満たさない関数は宣言の時点でコンパイルに失敗する。

use crate::marker::{MDTO, Mコマンド, M入力, M状態};

/// 状態から外部向けの表示データを取り出す一方向の射影の関数型。
pub type M射影関数<状態, 射影DTO> = fn(&状態) -> 射影DTO;

/// 生の入力から主体のコマンドを導く純粋な解釈の関数型。
pub type M解釈関数<入力, コマンド> = fn(&入力) -> コマンド;

/// 射影関数の型引数が `M状態` と `MDTO` を満たすことをコンパイラに確かめさせる恒等の関数。
pub const fn 射影関数として確認する<状態: M状態, 射影DTO: MDTO>(関数: M射影関数<状態, 射影DTO>) -> M射影関数<状態, 射影DTO> {
    関数
}

/// 解釈関数の型引数が `M入力` と `Mコマンド` を満たすことをコンパイラに確かめさせる恒等の関数。
pub const fn 解釈関数として確認する<入力: M入力, コマンド: Mコマンド>(関数: M解釈関数<入力, コマンド>) -> M解釈関数<入力, コマンド> {
    関数
}
