//! 関数の設計上の役割を表す、境界付きの newtype。
//!
//! 型エイリアスに書いた境界は強制されない(rust-lang/rust#112792)。そのため役割は関数ポインタを包む構造体で表し、
//! 型引数の境界を構造体の宣言に書く。構造体の境界は利用箇所でコンパイラが強制するため、型を使った時点で
//! 型引数が役割を満たさない関数は宣言の時点でコンパイルに失敗する。迂回できる書き方は無い。

use crate::marker::{Mコマンド, Mデバイス生入力, M不変データ, M状態};

/// 状態から外部向けの表示データを取り出す一方向の射影。型引数の境界は利用箇所でコンパイラが強制する。
#[derive(Clone, Copy)]
pub struct M射影関数<状態: M状態, 射影DTO: M不変データ>(fn(&状態) -> 射影DTO);

impl<状態: M状態, 射影DTO: M不変データ> M射影関数<状態, 射影DTO> {
    /// 関数を射影の役割で包む。
    pub const fn 生成する(関数: fn(&状態) -> 射影DTO) -> Self {
        Self(関数)
    }

    /// 包んだ関数を状態へ適用し、射影DTOを得る。
    pub fn 呼び出す(&self, 状態: &状態) -> 射影DTO {
        (self.0)(状態)
    }
}

/// 生の入力から主体のコマンドを導く純粋な解釈。型引数の境界は利用箇所でコンパイラが強制する。
#[derive(Clone, Copy)]
pub struct M解釈関数<入力: Mデバイス生入力, コマンド: Mコマンド>(fn(&入力) -> コマンド);

impl<入力: Mデバイス生入力, コマンド: Mコマンド> M解釈関数<入力, コマンド> {
    /// 関数を解釈の役割で包む。
    pub const fn 生成する(関数: fn(&入力) -> コマンド) -> Self {
        Self(関数)
    }

    /// 包んだ関数を入力へ適用し、コマンドを得る。
    pub fn 呼び出す(&self, 入力: &入力) -> コマンド {
        (self.0)(入力)
    }
}
