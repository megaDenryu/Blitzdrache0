//! 組み立てたシーン: 焼く工程が組み立てたシーンデータと、その組み立てで置いた個体の数を1つにした値。
//! シーンを実行時形式へ落とす工程はこの値だけを受け取る。
//!
//! 2つを1つの値にするのは、置いた個体の数を添えずにシーンを焼く道を残さないためである。数を省くと0が補われる口を
//! 残すと、群を作る工程が新しく増えたときに数え落としが黙って通り、実行時カタログの個体数との突き合わせが
//! 「載せ漏れ」でなく「数え忘れ」で落ちる。群を1つも作らない工程は、そのことを名前で述べる口から作る。

use blitz_engine::シーンデータ;

use crate::placed_instance_count::置いた個体の数;

pub(crate) struct 組み立てたシーン {
    pub(crate) シーン: シーンデータ,
    pub(crate) 置いた個体の数: 置いた個体の数,
}

impl 組み立てたシーン {
    /// インスタンス群を1つも持たないシーン。地形メッシュとglTFのシーンだけを持つ工程がこの口から作る。
    pub(crate) fn 群を持たないシーンから生成する(シーン: シーンデータ) -> Self {
        Self {
            シーン,
            置いた個体の数: 置いた個体の数::零(),
        }
    }

    pub(crate) fn 置いた個体の数を添えて生成する(シーン: シーンデータ, 置いた個体の数: 置いた個体の数) -> Self {
        Self {
            シーン, 置いた個体の数
        }
    }
}
