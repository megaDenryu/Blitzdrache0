//! 世界に1枚だけの遠景地形を焼くかどうかの指定と、プロセス境界でそれを運ぶ綴り。
//!
//! 世界の種別で決めないのは、同じ種別の世界が2つの規模で焼かれるためである。場所巡りの世界は3×3のクソゲーの
//! 世界としても8km×10kmの大規模世界としても焼かれ、違うのはアセットルートの中身だけである。種別で焼くと、
//! 3×3の遊ぶ世界のカタログにも遠景が入り、遠景の有無で大規模世界を見分ける実行時の判別が誤爆する。
//! 誤爆すると、遊ぶ世界の影が黙って明示境界へ移り、第4距離区分が空回りし、見えない遠景の面が毎フレーム描かれる。
//!
//! 綴りをこのライブラリが1つ持つのは、xtaskとアセットコンパイラの2つの実行ファイルが同じ語を使うためである。
//! 真偽の指定は綴りの有無で表すため、綴りがずれても知らない引数として黙って落ちる。片方だけを書き換えた食い違いが
//! 「遠景を焼いたつもりで焼いていない」形で出るのを防ぐには、綴りの出どころを1つにするしかない。
//!
//! 注意: この指定は焼き方の指定へ載り、生成台帳の見出しの一部になる。したがって指定を変えた実行は、
//! 材料が同じでもチャンク以外の生成物を焼き直す。

/// 遠景地形を焼くかどうか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 遠景地形の焼き方 {
    焼く,
    焼かない,
}

/// 引数の並びでこの指定を導く綴り。値を続けず、在ることが「焼く」を意味する。
const 選択肢の綴り: &str = "--bake-distant-terrain";

impl 遠景地形の焼き方 {
    /// 引数の並びからこの指定を取り除き、指定と残りの引数を返す。
    pub fn 引数一覧から取り出す(引数一覧: &[String]) -> (Self, Vec<String>) {
        let 残り: Vec<String> = 引数一覧.iter().filter(|引数| 引数.as_str() != 選択肢の綴り).cloned().collect();
        if 残り.len() == 引数一覧.len() {
            (Self::焼かない, 残り)
        } else {
            (Self::焼く, 残り)
        }
    }

    /// 焼かせる側が引数の並びへ足す綴り。焼かないときは1語も足さない。
    pub fn 引数へ足す綴り(self) -> Option<&'static str> {
        match self {
            Self::焼く => Some(選択肢の綴り),
            Self::焼かない => None,
        }
    }

    /// 焼き方の指定の綴りへ載せる語。生成台帳の見出しの一部になる。
    pub fn 台帳へ載せる綴り(self) -> &'static str {
        match self {
            Self::焼く => "焼く",
            Self::焼かない => "焼かない",
        }
    }

    pub fn 焼くか(self) -> bool {
        self == Self::焼く
    }
}

#[cfg(test)]
mod tests {
    use super::遠景地形の焼き方;

    /// 焼かせる側が足す綴りを、焼く側がそのまま読み戻せる。2つの実行ファイルの受け渡しがこの往復に依る。
    #[test]
    fn 足した綴りを読み戻すと同じ指定になる() {
        for 指定 in [遠景地形の焼き方::焼く, 遠景地形の焼き方::焼かない] {
            let mut 引数一覧 = vec!["ソース".to_string(), "出力".to_string()];
            引数一覧.extend(指定.引数へ足す綴り().map(str::to_string));
            let (読んだ, 残り) = 遠景地形の焼き方::引数一覧から取り出す(&引数一覧);
            assert_eq!(読んだ, 指定);
            assert_eq!(残り, vec!["ソース".to_string(), "出力".to_string()]);
        }
    }

    /// 綴りが無い引数の並びは「焼かない」である。既定で焼かないことが、3×3の遊ぶ世界を守る。
    #[test]
    fn 綴りが無ければ焼かない() {
        let (読んだ, _) = 遠景地形の焼き方::引数一覧から取り出す(&["世界".to_string()]);
        assert_eq!(読んだ, 遠景地形の焼き方::焼かない);
    }

    /// 台帳へ載せる綴りが指定ごとに違う。同じなら、指定を変えた実行が前の生成物を据え置く。
    #[test]
    fn 台帳へ載せる綴りが指定ごとに違う() {
        assert_ne!(遠景地形の焼き方::焼く.台帳へ載せる綴り(), 遠景地形の焼き方::焼かない.台帳へ載せる綴り());
    }
}
