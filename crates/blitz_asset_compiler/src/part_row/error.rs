//! 部品で組んだ並びを焼くときの失敗。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! アセットコンパイルエラーへ直に枝を足さずこの型を挟むのは、部品で組んだ並びだけが持つ前提(件数・部品の宣言・規則と宣言の食い違い)を
//! 1箇所へ集めるためである。上位の型は`#[from]`で1枝だけを持ち、どの世界の失敗かが枝の名前で分かる。

use blitz_assembly::展開エラー;
use thiserror::Error;

use crate::loader::部品カタログの読み込みエラー;

#[derive(Debug, Error)]
pub enum 部品で組んだ並びのコンパイルエラー {
    #[error("部品で組んだ並びへ据える件数が1以上{上限}以下でない: {実値}")]
    件数が範囲外 { 実値: usize, 上限: u16 }, // 1件も組まない並びは群を持たず、絵にも計器にも何も出ない

    #[error("部品で組んだ並びが読む部品が1件も宣言されていない")]
    部品が1件も宣言されていない,

    #[error("部品カタログを組み上げられない: {0}")]
    部品カタログを組めない(#[from] 部品カタログの読み込みエラー),

    #[error("展開が据えた部品{部品の綴り}の原型が部品で組んだ並びの宣言に無い")]
    据えた部品が宣言に無い { 部品の綴り: String }, // 規則が宣言していない部品を指している

    #[error("並びの{件の番号}件目を展開できない: {誤り}")]
    並びの1件を展開できない {
        件の番号: u16,
        #[source]
        誤り: 展開エラー,
    },
}
