//! 部品で組んだ並びの展開係: 部品カタログと敷地を保持し、規則を件数ぶん展開して1つの集約へまとめる操作サービス。
//!
//! 展開器と敷地を保持するのは、この2つが1つの並びを焼くあいだ変わらないためである。1件ごとに引数で渡すと、
//! 別のカタログと別の敷地を組み合わせた呼び出しが型を通る。
//!
//! **集約がここで作られることが、発行数が件数に比例しないことの実装である。** 1件ごとに出た配置表を
//! 部品の種類ごとの1つの配置列へ畳むため、件数が増えても描画対象の数は変わらない。

use blitz_assembly::{展開器, 生成の種, 組み立て規則, 部品ごとの配置の集約, 部品カタログ};

use super::error::部品で組んだ並びのコンパイルエラー;
use super::row_count::部品で組んだ並びの件数;
use super::site::部品で組んだ並びの敷地;
use crate::error::アセットコンパイルエラー;

pub(super) struct 部品で組んだ並びの展開係<'格子> {
    展開器: 展開器,
    敷地: 部品で組んだ並びの敷地<'格子>,
}

impl<'格子> 部品で組んだ並びの展開係<'格子> {
    pub(super) fn 生成する(カタログ: 部品カタログ, 敷地: 部品で組んだ並びの敷地<'格子>) -> Self {
        Self {
            展開器: 展開器::カタログを持たせて生成する(カタログ),
            敷地,
        }
    }

    /// 1件ごとに種を分けて展開し、部品の種類ごとの配置列へまとめる。
    /// 種を件の番号で分けるのは、同じ種のままだと全件が同じ形になり、組み合わせで違いを作る設計が絵に出ないためである。
    pub(super) fn 件数ぶん展開する(
        &self,
        規則: &組み立て規則,
        種の起点: 生成の種,
        件数: 部品で組んだ並びの件数,
    ) -> Result<部品ごとの配置の集約, アセットコンパイルエラー> {
        let mut 集約 = 部品ごとの配置の集約::空から始める();
        for 件の番号 in 0..件数.値() {
            let 根の配置 = self.敷地.並びの1件の根の配置を求める(件の番号)?;
            let 種 = 種の起点.個体の番号で分けた種を作る(u64::from(件の番号));
            let 配置表 = self
                .展開器
                .規則から展開する(規則, 種, 根の配置)
                .map_err(|誤り| 部品で組んだ並びのコンパイルエラー::並びの1件を展開できない { 件の番号, 誤り })?;
            集約.配置表を1件取り込む(&配置表);
        }
        Ok(集約)
    }
}
