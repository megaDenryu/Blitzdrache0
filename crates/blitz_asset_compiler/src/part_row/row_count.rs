//! 部品で組んだ並びの件数: 1つのチャンクへ組み上げる個体の数。家なら件数、木なら本数である。
//!
//! 裸のusizeで持たないのは、件数と部品の件数と個体の件数がどれも数であり、引数として並べると取り違えても署名が通るためである。
//! 上限をu16の範囲に置くのは、件の番号をそのまま格子の行と列へ割るためである。
//!
//! 据える場所の並べ方をこの型が答えるのは、列数が件数だけから決まるためである。呼び出し側が平方根を取り直すと、
//! 10件と100件で違う丸め方をした形が生まれる。

use super::error::部品で組んだ並びのコンパイルエラー;

/// 件数の上限。一辺100メートルのチャンクへ間隔10メートルで並べられるのは高々100件であり、
/// 段4の実証はその範囲で足りる。上限を置くと格子の列数の探索がu16の範囲で必ず止まる。
const 件数の上限: u16 = 1024;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct 部品で組んだ並びの件数(u16);

impl 部品で組んだ並びの件数 {
    pub fn 生成する(件数: usize) -> Result<Self, 部品で組んだ並びのコンパイルエラー> {
        let 範囲外 = || 部品で組んだ並びのコンパイルエラー::件数が範囲外 {
            実値: 件数,
            上限: 件数の上限,
        };
        let 値 = u16::try_from(件数).map_err(|_| 範囲外())?;
        if 値 == 0 || 値 > 件数の上限 {
            return Err(範囲外());
        }
        Ok(Self(値))
    }

    pub fn 値(self) -> u16 {
        self.0
    }

    /// 並べる正方に近い格子の列数。件数を覆う最小の正方格子の一辺である。
    pub fn 格子の列数(self) -> u16 {
        let mut 列数 = 1_u16;
        while u32::from(列数) * u32::from(列数) < u32::from(self.0) {
            列数 += 1;
        }
        列数
    }

    /// その列数で並べたときの行数。最後の行は埋まりきらないことがある。
    pub fn 格子の行数(self) -> u16 {
        let 列数 = self.格子の列数();
        self.0.div_ceil(列数)
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::部品で組んだ並びの件数;

    #[test]
    fn 零件と上限超えを拒む() {
        assert!(部品で組んだ並びの件数::生成する(0).is_err());
        assert!(部品で組んだ並びの件数::生成する(100_000).is_err());
    }

    #[test]
    fn 格子は件数を覆う() {
        for 件数 in [1_usize, 2, 9, 10, 99, 100] {
            let 値 = 部品で組んだ並びの件数::生成する(件数).unwrap();
            let 収まる数 = u32::from(値.格子の列数()) * u32::from(値.格子の行数());
            assert!(収まる数 >= u32::try_from(件数).unwrap(), "{件数}件が格子へ収まらない");
        }
    }

    #[test]
    fn 百件は十列十行になる() {
        let 百件 = 部品で組んだ並びの件数::生成する(100).unwrap();
        assert_eq!(百件.格子の列数(), 10);
        assert_eq!(百件.格子の行数(), 10);
    }
}
