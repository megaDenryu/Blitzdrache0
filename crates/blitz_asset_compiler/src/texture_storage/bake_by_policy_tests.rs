//! 方針と役割の組から決まる格納形式と、ブロック圧縮が不透明でない画素を拒むことの検査。

#![allow(clippy::unwrap_used)]

use blitz_engine::texture_storage::テクスチャ格納形式;
use blitz_engine::テクスチャデータ;

use super::storage_policy::{テクスチャ格納方針, 材質テクスチャ役割};
use super::方針と役割に従って原寸を格納済みテクスチャへ焼く;
use crate::error::アセットコンパイルエラー;

fn 一様な原寸を作る(画素: [u8; 4]) -> テクスチャデータ {
    テクスチャデータ {
        幅: 4,
        高さ: 4,
        rgba8: 画素.repeat(16),
    }
}

#[test]
fn 全てrgba8の方針はどの役割も非圧縮で焼く() {
    for 役割 in [
        材質テクスチャ役割::ベースカラー,
        材質テクスチャ役割::金属粗さ,
        材質テクスチャ役割::法線マップ,
    ] {
        let 焼いた = 方針と役割に従って原寸を格納済みテクスチャへ焼く(
            テクスチャ格納方針::全てRGBA8,
            役割,
            &一様な原寸を作る([10, 20, 30, 255]),
        )
        .unwrap();
        assert_eq!(焼いた.格納形式を返す(), テクスチャ格納形式::RGBA8);
        assert_eq!(焼いた.段ごとのバイト列を返す().len(), 1);
    }
}

#[test]
fn ブロック圧縮の方針はベースカラーだけを全段のbc1で焼く() {
    let 方針 = テクスチャ格納方針::ベースカラーのブロック圧縮;
    let ベースカラー = 方針と役割に従って原寸を格納済みテクスチャへ焼く(
        方針,
        材質テクスチャ役割::ベースカラー,
        &一様な原寸を作る([10, 20, 30, 255]),
    )
    .unwrap();
    assert_eq!(ベースカラー.格納形式を返す(), テクスチャ格納形式::BC1);
    assert_eq!(ベースカラー.段ごとのバイト列を返す().len(), 3);

    let 法線 = 方針と役割に従って原寸を格納済みテクスチャへ焼く(
        方針,
        材質テクスチャ役割::法線マップ,
        &一様な原寸を作る([128, 128, 255, 255]),
    )
    .unwrap();
    assert_eq!(法線.格納形式を返す(), テクスチャ格納形式::RGBA8);
}

#[test]
fn ブロック圧縮のベースカラーは不透明でない画素を拒む() {
    let 誤り = 方針と役割に従って原寸を格納済みテクスチャへ焼く(
        テクスチャ格納方針::ベースカラーのブロック圧縮,
        材質テクスチャ役割::ベースカラー,
        &一様な原寸を作る([10, 20, 30, 128]),
    );
    assert!(matches!(
        誤り,
        Err(アセットコンパイルエラー::ブロック圧縮のベースカラーに不透明でない画素がある {
            画素番号: 0,
            不透明度: 128
        })
    ));
}
