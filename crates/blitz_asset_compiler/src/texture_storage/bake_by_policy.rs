//! テクスチャ格納方針と材質テクスチャ役割から、復号済みの原寸を実行時形式が運ぶ形へ焼く工程。
//! 受け取るのは方針と役割と原寸、返すのは格納済みテクスチャである。
//! ブロック圧縮の格納は縮小段の連なりも同時に焼く。実行時の縮小段の生成はブロック圧縮の画像へ書き込めないためである。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`「判断d」

use blitz_engine::texture_storage::{テクスチャ格納形式, 格納済みテクスチャ};
use blitz_engine::テクスチャデータ;

use super::srgbの色の全段をbc1のバイト列へ符号化する;
use super::storage_policy::{テクスチャ格納方針, 材質テクスチャ役割};
use crate::error::アセットコンパイルエラー;

/// 不透明である画素の不透明度。BC1は不透明度を運ばないため、これ以外の値を持つ画像は焼けない。
const 不透明の不透明度: u8 = 255;

pub fn 方針と役割に従って原寸を格納済みテクスチャへ焼く(
    方針: テクスチャ格納方針,
    役割: 材質テクスチャ役割,
    原寸: &テクスチャデータ,
) -> Result<格納済みテクスチャ, アセットコンパイルエラー> {
    match 方針.役割に割り当てる格納形式を返す(役割) {
        テクスチャ格納形式::RGBA8 => Ok(格納済みテクスチャ::rgba8の原寸から生成する(原寸)?),
        テクスチャ格納形式::BC1 => {
            全画素が不透明かを検査する(原寸)?;
            let 全段 = srgbの色の全段をbc1のバイト列へ符号化する(原寸)?;
            Ok(格納済みテクスチャ::生成する(
                原寸.幅,
                原寸.高さ,
                テクスチャ格納形式::BC1,
                全段,
            )?)
        }
    }
}

/// BC1は色の3成分だけを運び、不透明度を捨てる。半透明の画素を無言で不透明へ倒すと絵が作者の宣言と食い違うため、
/// 不透明でない画素を1つでも見つけた時点で焼くことを拒む。
fn 全画素が不透明かを検査する(原寸: &テクスチャデータ) -> Result<(), アセットコンパイルエラー> {
    for (画素番号, 画素) in 原寸.rgba8.chunks_exact(4).enumerate() {
        let 不透明度 = 画素[3];
        if 不透明度 != 不透明の不透明度 {
            return Err(アセットコンパイルエラー::ブロック圧縮のベースカラーに不透明でない画素がある {
                画素番号,
                不透明度,
            });
        }
    }
    Ok(())
}
