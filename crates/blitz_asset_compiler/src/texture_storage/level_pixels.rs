//! 縮小段の画素の読み出し口: 1段の寸法と画素列の長さの一致を確かめた上で保持し、座標で1画素を読む型である。
//! 段の外を指す座標を端の行・列へ丸めるため、ブロック圧縮のブロックの埋め方(右下の端の画素の複製)と
//! 2x2平均の縮小の端の扱いが、同じ1つの丸めの規則を使う。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`

use blitz_engine::texture_storage::{テクスチャ格納形式, 縮小段の寸法};
use blitz_engine::テクスチャデータ;

use crate::error::アセットコンパイルエラー;

/// 1画素4バイトの並びの中での成分の位置。この順序を知るのはこのモジュールと画素色の型だけである。
pub const 赤の位置: usize = 0;
pub const 緑の位置: usize = 1;
pub const 青の位置: usize = 2;
pub const 不透明度の位置: usize = 3;

/// 添字の算術に使う1画素のバイト数。エンジンの`テクスチャ格納形式::RGBA8`が数える1画素と同じ4である。
const 画素1つのバイト数: usize = 4;

pub struct 縮小段の画素の読み出し口<'a> {
    幅: usize,
    高さ: usize,
    rgba8: &'a [u8],
}

impl<'a> 縮小段の画素の読み出し口<'a> {
    /// 零の寸法と、寸法と食い違う長さの画素列を拒む。以後の読み出しはこの検査に守られて範囲内に収まる。
    /// 期待する長さはエンジンの格納バイト数の算術から得るため、焼く側と読む側が同じ数え方を使う。
    pub fn 生成する(段: &'a テクスチャデータ) -> Result<Self, アセットコンパイルエラー> {
        let 期待する長さ = テクスチャ格納形式::RGBA8.縮小段の格納バイト数を求める(縮小段の寸法::生成する(段.幅, 段.高さ)?)?;
        let 期待する長さ = usize::try_from(期待する長さ)
            .map_err(|_| アセットコンパイルエラー::テクスチャの格納バイト数が添字の型に収まらない(期待する長さ))?;
        if 段.rgba8.len() != 期待する長さ {
            return Err(アセットコンパイルエラー::縮小段の画素列の長さが寸法と食い違う {
                幅: 段.幅,
                高さ: 段.高さ,
                長さ: 段.rgba8.len(),
            });
        }
        Ok(Self {
            幅: 寸法を添字の型へ広げる(段.幅)?,
            高さ: 寸法を添字の型へ広げる(段.高さ)?,
            rgba8: &段.rgba8,
        })
    }

    /// 段の外を指す座標は端の行・列へ丸める。返す4バイトは赤・緑・青・不透明度の順である。
    pub fn 端で丸めて画素を読む(&self, 横: usize, 縦: usize) -> [u8; 4] {
        let 丸めた横 = 横.min(self.幅 - 1);
        let 丸めた縦 = 縦.min(self.高さ - 1);
        let 先頭 = (丸めた縦 * self.幅 + 丸めた横) * 画素1つのバイト数;
        [
            self.rgba8[先頭 + 赤の位置],
            self.rgba8[先頭 + 緑の位置],
            self.rgba8[先頭 + 青の位置],
            self.rgba8[先頭 + 不透明度の位置],
        ]
    }
}

/// 32ビットの寸法を添字の型へ広げる。usizeが32ビットに満たない環境では表せない寸法があるため結果で返す。
pub fn 寸法を添字の型へ広げる(寸法: u32) -> Result<usize, アセットコンパイルエラー> {
    usize::try_from(寸法).map_err(|_| アセットコンパイルエラー::テクスチャの寸法が添字の型に収まらない(寸法))
}
