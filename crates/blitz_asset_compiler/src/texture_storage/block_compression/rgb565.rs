//! RGB565の端点色: BC1の1ブロックが持つ2つの端点である。赤5ビット・緑6ビット・青5ビットを
//! 16ビットへ詰めた形で保持し、GPUの復号と同じ規則(上位ビットを下位へ複製する)で8ビットの色へ戻す。
//! 端点の順序が3色モードと4色モードのどちらを選ぶかを決めるため、詰めた値そのものも取り出せる。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`

use super::super::pixel_color::ブロックの画素色;

const 赤の段数: u16 = 31;
const 緑の段数: u16 = 63;
const 青の段数: u16 = 31;

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct RGB565の端点色(u16);

impl RGB565の端点色 {
    /// 8ビットの成分を最も近い段へ丸める。ちょうど中間にある値は小さい側の段へ落とす。
    pub fn 画素の色から量子化する(色: ブロックの画素色) -> Self {
        let 赤 = 成分を段へ量子化する(色.赤, 赤の段数);
        let 緑 = 成分を段へ量子化する(色.緑, 緑の段数);
        let 青 = 成分を段へ量子化する(色.青, 青の段数);
        Self((赤 << 11) | (緑 << 5) | 青)
    }

    pub fn 詰めた値を返す(self) -> u16 {
        self.0
    }

    /// 段の上位ビットを下位へ複製して8ビットへ広げる。GPUのBC1の復号が使う規則と同じである。
    pub fn 画素の色へ復元する(self) -> ブロックの画素色 {
        let [上位, 下位] = self.0.to_be_bytes();
        let 赤 = 上位 >> 3;
        let 緑 = ((上位 & 0b0000_0111) << 3) | (下位 >> 5);
        let 青 = 下位 & 0b0001_1111;
        ブロックの画素色 {
            赤: (赤 << 3) | (赤 >> 2),
            緑: (緑 << 2) | (緑 >> 4),
            青: (青 << 3) | (青 >> 2),
        }
    }
}

/// 段数nに対して`(値 * n + 127) / 255`を返す。整数だけで最も近い段へ丸めるための式である。
fn 成分を段へ量子化する(値: u8, 段数: u16) -> u16 {
    (u16::from(値) * 段数 + 127) / 255
}
