//! 縮小段1段を4x4のブロックへ区切って走査し、全ブロックのBC1のバイト列を作る工程。
//! ブロックの並びは左上から行優先である。幅または高さが4の倍数でない段と2x2・1x1の段は、
//! 右下の端の画素を複製してブロックを埋める(この複製は読み出し口の丸めの規則が行う)。
//! 受け取るのは1段のテクスチャデータ、返すのはその段のBC1のバイト列である。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`

use blitz_engine::texture_storage::{ブロックの一辺の画素数, ブロック格子};
use blitz_engine::テクスチャデータ;

use crate::error::アセットコンパイルエラー;

use super::super::level_pixels::{寸法を添字の型へ広げる, 縮小段の画素の読み出し口};
use super::super::pixel_color::ブロックの画素色;
use super::block_encode::{ブロック1つの画素数, ブロックの画素をbc1の8バイトへ符号化する};

pub fn rgba8の縮小段をbc1のバイト列へ符号化する(
    段: &テクスチャデータ
) -> Result<Vec<u8>, アセットコンパイルエラー> {
    let 格子 = ブロック格子::生成する(段.幅, 段.高さ)?;
    let 読み出し口 = 縮小段の画素の読み出し口::生成する(段)?;
    let 一辺 = 寸法を添字の型へ広げる(ブロックの一辺の画素数)?;
    let 横のブロック数 = 寸法を添字の型へ広げる(格子.横のブロック数を返す())?;
    let 縦のブロック数 = 寸法を添字の型へ広げる(格子.縦のブロック数を返す())?;
    let mut バイト列 = Vec::with_capacity(横のブロック数 * 縦のブロック数 * 8);
    for 縦のブロック位置 in 0..縦のブロック数 {
        for 横のブロック位置 in 0..横のブロック数 {
            let 画素一覧 = ブロックの画素を端の複製で切り出す(&読み出し口, 横のブロック位置 * 一辺, 縦のブロック位置 * 一辺, 一辺);
            バイト列.extend_from_slice(&ブロックの画素をbc1の8バイトへ符号化する(&画素一覧));
        }
    }
    Ok(バイト列)
}

fn ブロックの画素を端の複製で切り出す(
    読み出し口: &縮小段の画素の読み出し口<'_>,
    左端: usize,
    上端: usize,
    一辺: usize,
) -> [ブロックの画素色; ブロック1つの画素数] {
    let mut 画素一覧 = [ブロックの画素色::画素の4バイトから生成する(読み出し口.端で丸めて画素を読む(左端, 上端)); ブロック1つの画素数];
    for (位置, 画素) in 画素一覧.iter_mut().enumerate() {
        let 読んだ4バイト = 読み出し口.端で丸めて画素を読む(左端 + 位置 % 一辺, 上端 + 位置 / 一辺);
        *画素 = ブロックの画素色::画素の4バイトから生成する(読んだ4バイト);
    }
    画素一覧
}
