//! 符号化の検査が使う素材の組み立て。ブロック1つぶんの16画素と、寸法を指定した1段の画素列を作る。
//! 素材を1箇所へ集めることで、期待バイト列を固定する検査と往復の誤差を見る検査が同じ入力を共有する。

use blitz_engine::テクスチャデータ;

use super::super::level_pixels::縮小段の画素の読み出し口;
use super::super::pixel_color::ブロックの画素色;
use super::block_encode::ブロック1つの画素数;

/// 左の2列が黒、右の2列が白のブロック。
pub fn 二色の縦縞のブロックを作る() -> [ブロックの画素色; ブロック1つの画素数] {
    let mut 画素一覧 = [ブロックの画素色 { 赤: 0, 緑: 0, 青: 0 }; ブロック1つの画素数];
    for (位置, 画素) in 画素一覧.iter_mut().enumerate() {
        if 位置 % 4 >= 2 {
            *画素 = ブロックの画素色 {
                赤: 255, 緑: 255, 青: 255
            };
        }
    }
    画素一覧
}

pub fn 単色のブロックを作る(赤: u8, 緑: u8, 青: u8) -> [ブロックの画素色; ブロック1つの画素数] {
    [ブロックの画素色 { 赤, 緑, 青 }; ブロック1つの画素数]
}

pub fn 一様な段を作る(幅: u32, 高さ: u32, 画素: [u8; 4]) -> テクスチャデータ {
    let 画素数 = 添字の型へ広げる(幅) * 添字の型へ広げる(高さ);
    テクスチャデータ {
        幅,
        高さ,
        rgba8: 画素.repeat(画素数),
    }
}

/// 横位置だけで色が決まる段。どの列も縦に一様であるため、端の列を複製したブロックは単色になる。
pub fn 縦縞の段を作る(幅: u32, 高さ: u32) -> テクスチャデータ {
    let mut rgba8 = Vec::new();
    for _ in 0..高さ {
        for 横 in 0..幅 {
            let 明るさ = 明るさへ狭める((横 * 37) % 256);
            rgba8.extend_from_slice(&[明るさ, 255 - 明るさ, 明るさ / 2, 255]);
        }
    }
    テクスチャデータ { 幅, 高さ, rgba8 }
}

/// 段の画素を行優先の色の一覧として取り出す。期待値の組み立てが読み出し口の丸めに依存しないようにする。
pub fn 段の色を並べる(段: &テクスチャデータ) -> Vec<ブロックの画素色> {
    let 読み出し口 = 縮小段の画素の読み出し口::生成する(段).unwrap_or_else(|誤り| panic!("検査の段が読み出し口を作れない: {誤り}"));
    let mut 一覧 = Vec::new();
    for 縦 in 0..添字の型へ広げる(段.高さ) {
        for 横 in 0..添字の型へ広げる(段.幅) {
            一覧.push(ブロックの画素色::画素の4バイトから生成する(
                読み出し口.端で丸めて画素を読む(横, 縦),
            ));
        }
    }
    一覧
}

fn 添字の型へ広げる(値: u32) -> usize {
    usize::try_from(値).unwrap_or_else(|_| panic!("検査の寸法が添字の型に収まらない: {値}"))
}

fn 明るさへ狭める(値: u32) -> u8 {
    u8::try_from(値).unwrap_or_else(|_| panic!("検査の明るさが8ビットに収まらない: {値}"))
}
