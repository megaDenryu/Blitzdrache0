//! ブロックの16画素から端点の候補となる2色を選ぶ工程。ブロック内で二乗距離が最も大きい2画素の色を採る。
//! これは設計正本が端点の探索に許した「最も長い対角」であり、全て整数の演算で決まるため
//! 同じ入力からは常に同じ2色が出る。等しい距離の組が複数あるときは走査順で最初の組を採る。
//! 受け取るのはブロックの16画素、返すのは順序を持たない2色である(BC1の端点の順序の強制は符号化の側が行う)。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`

use super::super::pixel_color::ブロックの画素色;

pub fn ブロックの色から最も離れた2色を選ぶ(
    画素一覧: &[ブロックの画素色; 16],
) -> (ブロックの画素色, ブロックの画素色) {
    let mut 最も離れた組 = (画素一覧[0], 画素一覧[0]);
    let mut 最大の二乗距離 = 0;
    for (先の位置, 先の色) in 画素一覧.iter().enumerate() {
        for 後の色 in &画素一覧[先の位置 + 1..] {
            let 二乗距離 = 先の色.相手までの二乗距離を返す(*後の色);
            if 二乗距離 > 最大の二乗距離 {
                最大の二乗距離 = 二乗距離;
                最も離れた組 = (*先の色, *後の色);
            }
        }
    }
    最も離れた組
}
