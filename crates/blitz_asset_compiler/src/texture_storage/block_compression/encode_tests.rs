//! BC1の符号化の検査。既知のブロックの期待バイト列の固定、単色のブロックの決着、端の画素の複製、
//! 参照の復号器との往復の誤差の上界を見る。

#![allow(clippy::unwrap_used)]

use blitz_engine::texture_storage::テクスチャ格納形式;
use blitz_engine::テクスチャデータ;

use super::super::pixel_color::ブロックの画素色;
use super::block_encode::ブロックの画素をbc1の8バイトへ符号化する;
use super::block_scan::rgba8の縮小段をbc1のバイト列へ符号化する;
use super::reference_decode::bc1の8バイトをブロックの16画素へ復号する;
use super::rgb565::RGB565の端点色;

use super::encode_test_fixture::{
    一様な段を作る, 二色の縦縞のブロックを作る, 単色のブロックを作る, 段の色を並べる, 縦縞の段を作る
};

/// 左半分が黒、右半分が白のブロック。端点は黒と白であり、4色モードの順序へ入れ替わる。
#[test]
fn 二色のブロックの期待バイト列を固定する() {
    let バイト列 = ブロックの画素をbc1の8バイトへ符号化する(&二色の縦縞のブロックを作る());
    assert_eq!(バイト列, [0xFF, 0xFF, 0x00, 0x00, 0x05, 0x05, 0x05, 0x05]);
}

/// 単色のブロックはRGB565へ量子化した端点が一致するため、3色モードのまま索引を全て0にする。
#[test]
fn 単色のブロックは索引を全て零にする() {
    let 端点 = RGB565の端点色::画素の色から量子化する(ブロックの画素色 { 赤: 255, 緑: 0, 青: 0 });
    let バイト列 = ブロックの画素をbc1の8バイトへ符号化する(&単色のブロックを作る(255, 0, 0));
    let [下位, 上位] = 端点.詰めた値を返す().to_le_bytes();
    assert_eq!(バイト列, [下位, 上位, 下位, 上位, 0, 0, 0, 0]);
}

#[test]
fn 単色のブロックは全画素が量子化した1色へ復号される() {
    let バイト列 = ブロックの画素をbc1の8バイトへ符号化する(&単色のブロックを作る(200, 100, 50));
    let 期待する色 = RGB565の端点色::画素の色から量子化する(ブロックの画素色 { 赤: 200, 緑: 100, 青: 50 }).画素の色へ復元する();
    for 画素 in bc1の8バイトをブロックの16画素へ復号する(バイト列) {
        assert_eq!(画素, Some(期待する色));
    }
}

#[test]
fn 段のバイト数はエンジンの算術と一致する() {
    for (幅, 高さ) in [(4, 4), (5, 3), (1, 1), (16, 16), (7, 9)] {
        let 段 = 一様な段を作る(幅, 高さ, [10, 200, 30, 255]);
        let バイト列 = rgba8の縮小段をbc1のバイト列へ符号化する(&段).unwrap();
        let 期待 = テクスチャ格納形式::BC1.縮小段の格納バイト数を求める(幅, 高さ).unwrap();
        assert_eq!(u64::try_from(バイト列.len()).unwrap(), 期待);
    }
}

/// 5x3の段の右下のブロックは、範囲の外を端の画素で埋めるため、その端の色だけの単色ブロックになる。
#[test]
fn 端の画素の複製でブロックを埋める() {
    let 段 = 縦縞の段を作る(5, 3);
    let バイト列 = rgba8の縮小段をbc1のバイト列へ符号化する(&段).unwrap();
    let 右のブロック: [u8; 8] = バイト列[8..16].try_into().unwrap();
    let 端の色 = 段の色を並べる(&段)[4];
    let 期待する色 = RGB565の端点色::画素の色から量子化する(端の色).画素の色へ復元する();
    for 画素 in bc1の8バイトをブロックの16画素へ復号する(右のブロック) {
        assert_eq!(画素, Some(期待する色));
    }
}

/// 2色しか持たないブロックは端点がその2色になるため、誤差はRGB565の量子化の1段の半分に収まる。
#[test]
fn 二色のブロックの往復の誤差は量子化の半段に収まる() {
    let バイト列 = ブロックの画素をbc1の8バイトへ符号化する(&二色の縦縞のブロックを作る());
    let 復号 = bc1の8バイトをブロックの16画素へ復号する(バイト列);
    for (位置, 画素) in 復号.into_iter().enumerate() {
        let 元 = 二色の縦縞のブロックを作る()[位置];
        let 画素 = 画素.unwrap();
        assert!(画素.赤.abs_diff(元.赤) <= 4, "赤の誤差が上界を超えた");
        assert!(画素.緑.abs_diff(元.緑) <= 2, "緑の誤差が上界を超えた");
        assert!(画素.青.abs_diff(元.青) <= 4, "青の誤差が上界を超えた");
    }
}

#[test]
fn 同じ入力からは常に同じバイト列が出る() {
    let 段 = 縦縞の段を作る(16, 16);
    let 一度目 = rgba8の縮小段をbc1のバイト列へ符号化する(&段).unwrap();
    let 二度目 = rgba8の縮小段をbc1のバイト列へ符号化する(&段).unwrap();
    assert_eq!(一度目, 二度目);
}

#[test]
fn 寸法と食い違う画素列を拒む() {
    let 段 = テクスチャデータ {
        幅: 4,
        高さ: 4,
        rgba8: vec![0; 4 * 4 * 4 - 1],
    };
    assert!(rgba8の縮小段をbc1のバイト列へ符号化する(&段).is_err());
}
