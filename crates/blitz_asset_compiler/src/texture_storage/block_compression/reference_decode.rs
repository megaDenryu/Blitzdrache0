//! 参照の復号器: BC1の8バイトを16画素へ戻す、検査だけが呼ぶ実装である。符号化器の部品を1つも呼ばず
//! 形式の規則から書き下ろすため、端点の詰め方・順序・補間のどこに誤りが入っても往復の検査が捕まえる。
//!
//! 注意: これは許容誤差の内側にある参照の実装であり、GPUの復号の厳密なCPU正本ではない。
//! BC1からBC3のGPUの復号には実装ごとの補間の差が許されているため、将来にわたって
//! GPUの出力とのバイト一致を主張する検査を置いてはならない。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`

use super::super::pixel_color::ブロックの画素色;

/// 3色モードの索引3は透過であり色を持たないため、その画素だけ不在を返す。
pub fn bc1の8バイトをブロックの16画素へ復号する(バイト列: [u8; 8]) -> [Option<ブロックの画素色>; 16] {
    let 色0の詰めた値 = u16::from_le_bytes([バイト列[0], バイト列[1]]);
    let 色1の詰めた値 = u16::from_le_bytes([バイト列[2], バイト列[3]]);
    let 色0 = 詰めた値を色へ広げる(色0の詰めた値);
    let 色1 = 詰めた値を色へ広げる(色1の詰めた値);
    let 四色 = if 色0の詰めた値 > 色1の詰めた値 {
        [Some(色0), Some(色1), Some(内分する(色0, 色1, 2, 1)), Some(内分する(色0, 色1, 1, 2))]
    } else {
        [Some(色0), Some(色1), Some(内分する(色0, 色1, 1, 1)), None]
    };
    let mut 画素一覧 = [None; 16];
    for (位置, 画素) in 画素一覧.iter_mut().enumerate() {
        let 索引 = (バイト列[4 + 位置 / 4] >> (2 * (位置 % 4))) & 0b11;
        *画素 = 四色[usize::from(索引)];
    }
    画素一覧
}

fn 詰めた値を色へ広げる(詰めた値: u16) -> ブロックの画素色 {
    ブロックの画素色 {
        赤: 五ビットの段を8ビットへ広げる(段を取り出す(詰めた値, 11, 0b1_1111)),
        緑: 六ビットの段を8ビットへ広げる(段を取り出す(詰めた値, 5, 0b11_1111)),
        青: 五ビットの段を8ビットへ広げる(段を取り出す(詰めた値, 0, 0b1_1111)),
    }
}

fn 段を取り出す(詰めた値: u16, 右へずらす幅: u32, 覆い: u16) -> u8 {
    let 段 = (詰めた値 >> 右へずらす幅) & 覆い;
    u8::try_from(段).unwrap_or_else(|_| panic!("RGB565の段が8ビットに収まらない: {段}"))
}

/// 形式が定める拡大の規則は上位ビットの下位への複製である。5ビットは3ビットぶん複製する。
fn 五ビットの段を8ビットへ広げる(段: u8) -> u8 {
    (段 << 3) | (段 >> 2)
}

fn 六ビットの段を8ビットへ広げる(段: u8) -> u8 {
    (段 << 2) | (段 >> 4)
}

fn 内分する(色0: ブロックの画素色, 色1: ブロックの画素色, 重み0: u16, 重み1: u16) -> ブロックの画素色 {
    ブロックの画素色 {
        赤: 成分を内分する(色0.赤, 色1.赤, 重み0, 重み1),
        緑: 成分を内分する(色0.緑, 色1.緑, 重み0, 重み1),
        青: 成分を内分する(色0.青, 色1.青, 重み0, 重み1),
    }
}

fn 成分を内分する(成分0: u8, 成分1: u8, 重み0: u16, 重み1: u16) -> u8 {
    let 値 = (u16::from(成分0) * 重み0 + u16::from(成分1) * 重み1) / (重み0 + 重み1);
    u8::try_from(値).unwrap_or_else(|_| panic!("内分の値が8ビットに収まらない: {値}"))
}
