//! BC1の四色表: 2つの端点が張る線分上の4色である。端点の詰めた値が`色0 > 色1`である4色モードだけを
//! 組み立てる。3色モードは端点が一致した単色のブロックの決着でだけ使い、そのとき索引は全て0であるため
//! 表を引かない。索引の割当もこの型が持つ(表を作った側だけが4色の並び順を知っているためである)。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`

use super::super::pixel_color::ブロックの画素色;
use super::rgb565::RGB565の端点色;

pub const 四色表の色数: u8 = 4;

pub struct BC1の四色表 {
    色一覧: [ブロックの画素色; 4],
}

impl BC1の四色表 {
    /// 前提: 呼び出し側が`端点0.詰めた値を返す() > 端点1.詰めた値を返す()`を保証している。
    /// この順序でなければGPUは3色モードとして復号し、索引2と3の意味が変わる。
    pub fn 四色モードで生成する(端点0: RGB565の端点色, 端点1: RGB565の端点色) -> Self {
        let 色0 = 端点0.画素の色へ復元する();
        let 色1 = 端点1.画素の色へ復元する();
        Self {
            色一覧: [色0, 色1, 二対一で混ぜる(色0, 色1), 二対一で混ぜる(色1, 色0)],
        }
    }

    /// 二乗距離が最も小さい色の索引を返す。等距離のときは小さい索引を選ぶため、同じ入力からは常に同じ索引が出る。
    pub fn 最も近い色の索引を返す(&self, 画素: ブロックの画素色) -> u8 {
        let mut 最良の索引 = 0;
        let mut 最小の二乗距離 = u32::MAX;
        for 索引 in 0..四色表の色数 {
            let 二乗距離 = self.色一覧[usize::from(索引)].相手までの二乗距離を返す(画素);
            if 二乗距離 < 最小の二乗距離 {
                最小の二乗距離 = 二乗距離;
                最良の索引 = 索引;
            }
        }
        最良の索引
    }
}

/// 多い側を2、少ない側を1の重みで混ぜる。除算の切り捨てはGPUの復号に許された実装差の内側にある。
fn 二対一で混ぜる(多い側: ブロックの画素色, 少ない側: ブロックの画素色) -> ブロックの画素色 {
    ブロックの画素色 {
        赤: 成分を二対一で混ぜる(多い側.赤, 少ない側.赤),
        緑: 成分を二対一で混ぜる(多い側.緑, 少ない側.緑),
        青: 成分を二対一で混ぜる(多い側.青, 少ない側.青),
    }
}

fn 成分を二対一で混ぜる(多い側: u8, 少ない側: u8) -> u8 {
    let 混ぜた値 = (u16::from(多い側) * 2 + u16::from(少ない側)) / 3;
    u8::try_from(混ぜた値).unwrap_or_else(|_| panic!("端点の内分の値が8ビットに収まらない: {混ぜた値}"))
}
