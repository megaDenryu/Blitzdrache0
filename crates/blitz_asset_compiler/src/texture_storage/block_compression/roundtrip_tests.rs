//! 参照の復号器との往復の誤差の上界の検査。段を符号化してから復号し、成分ごとの誤差が上界に収まることと、
//! 不透明なテクスチャが透過の枝へ1度も入らないことを見る。
//!
//! 上界を2つに分けるのは、BC1が1ブロックの色を2つの端点が張る1本の線分の上の4点で表す形式だからである。
//! ブロック内の色が線分の上に載る段では誤差は量子化の細かさで決まり、載らない段では線分からの隔たりが加わる。

#![allow(clippy::unwrap_used)]
#![allow(clippy::expect_used)]

use blitz_engine::テクスチャデータ;

use super::block_scan::rgba8の縮小段をbc1のバイト列へ符号化する;
use super::reference_decode::bc1の8バイトをブロックの16画素へ復号する;

use super::encode_test_fixture::段の色を並べる;

const 段の一辺: u32 = 32;

/// 全ての成分が横と縦の和だけで決まる色。1ブロックの16色が1本の線分の上に載る。
fn 横と縦の和だけで決まる色を返す(横: u32, 縦: u32) -> [u8; 4] {
    let 明るさ = u8::try_from((横 + 縦) * 255 / (2 * (段の一辺 - 1))).unwrap();
    [明るさ, 明るさ / 2, 255 - 明るさ, 255]
}

/// 赤が横だけ、緑が縦だけで決まる色。1ブロックの16色が平面へ広がり、1本の線分には載らない。
fn 赤と緑が別の軸で決まる色を返す(横: u32, 縦: u32) -> [u8; 4] {
    let 赤 = u8::try_from(横 * 255 / (段の一辺 - 1)).unwrap();
    let 緑 = u8::try_from(縦 * 255 / (段の一辺 - 1)).unwrap();
    [赤, 緑, 128, 255]
}

fn 段を組み立てる(色を決める: fn(u32, u32) -> [u8; 4]) -> テクスチャデータ {
    let mut rgba8 = Vec::new();
    for 縦 in 0..段の一辺 {
        for 横 in 0..段の一辺 {
            rgba8.extend_from_slice(&色を決める(横, 縦));
        }
    }
    テクスチャデータ {
        幅: 段の一辺,
        高さ: 段の一辺,
        rgba8,
    }
}

/// 段を符号化してから復号し、成分ごとの誤差の最大値を返す。
fn 往復の誤差の最大を求める(段: &テクスチャデータ) -> u8 {
    let バイト列 = rgba8の縮小段をbc1のバイト列へ符号化する(段).unwrap();
    let 元の色一覧 = 段の色を並べる(段);
    let mut 最大の誤差 = 0;
    for (ブロック番号, ブロックのバイト列) in バイト列.chunks_exact(8).enumerate() {
        let ブロックのバイト列: [u8; 8] = ブロックのバイト列.try_into().unwrap();
        for (位置, 画素) in bc1の8バイトをブロックの16画素へ復号する(ブロックのバイト列).into_iter().enumerate() {
            let 画素 = 画素.expect("不透明なテクスチャの符号化が透過の枝へ入った");
            let 元 = 元の色一覧[元の添字を求める(ブロック番号, 位置)];
            最大の誤差 = 最大の誤差
                .max(画素.赤.abs_diff(元.赤))
                .max(画素.緑.abs_diff(元.緑))
                .max(画素.青.abs_diff(元.青));
        }
    }
    最大の誤差
}

/// ブロックの走査順(左上から行優先)とブロック内の走査順から、段の中の位置を戻す。
fn 元の添字を求める(ブロック番号: usize, ブロック内の位置: usize) -> usize {
    let 一辺 = usize::try_from(段の一辺).unwrap();
    let 横のブロック数 = 一辺 / 4;
    let 横 = (ブロック番号 % 横のブロック数) * 4 + ブロック内の位置 % 4;
    let 縦 = (ブロック番号 / 横のブロック数) * 4 + ブロック内の位置 / 4;
    縦 * 一辺 + 横
}

/// 5はこの固定入力での実測の最大値をそのまま固定した値である(導出した上界ではない)。
/// 入力が固定で符号化が全整数のため値は揺れず、符号化を劣化させる変更はこの線で落ちる。
#[test]
fn 線分に載る段の往復の誤差が上界に収まる() {
    let 誤差 = 往復の誤差の最大を求める(&段を組み立てる(横と縦の和だけで決まる色を返す));
    assert!(誤差 <= 5, "線分に載る段の誤差が上界を超えた: {誤差}");
}

/// 17もこの固定入力(赤が横・緑が縦で独立に変わる、線分に載らない最悪形)での実測の最大値の固定である。
#[test]
fn 線分に載らない段でも往復の誤差に上界がある() {
    let 誤差 = 往復の誤差の最大を求める(&段を組み立てる(赤と緑が別の軸で決まる色を返す));
    assert!(誤差 <= 17, "線分に載らない段の誤差が上界を超えた: {誤差}");
}
