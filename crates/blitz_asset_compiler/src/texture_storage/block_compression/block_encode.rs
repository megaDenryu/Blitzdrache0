//! 4x4の16画素を1つのBC1のブロック(8バイト)へ符号化する工程。端点の順序の強制と単色のブロックの決着を
//! ここが持つ。受け取るのはブロックの16画素、返すのは先頭から色0・色1・索引の順に並べた8バイトである。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`

use super::super::pixel_color::ブロックの画素色;
use super::endpoint_search::ブロックの色から最も離れた2色を選ぶ;
use super::palette::BC1の四色表;
use super::rgb565::RGB565の端点色;

/// 1ブロックの画素数。BC1は4x4を1ブロックにする。
pub const ブロック1つの画素数: usize = 16;

/// 索引を詰める1バイトが受け持つ画素数。1画素が2ビットであるため4画素で1バイトになる。
const 索引1バイトあたりの画素数: usize = 4;

pub fn ブロックの画素をbc1の8バイトへ符号化する(
    画素一覧: &[ブロックの画素色; ブロック1つの画素数]
) -> [u8; 8] {
    let (色a, 色b) = ブロックの色から最も離れた2色を選ぶ(画素一覧);
    let 端点a = RGB565の端点色::画素の色から量子化する(色a);
    let 端点b = RGB565の端点色::画素の色から量子化する(色b);
    if 端点a == 端点b {
        return 単色のブロックのバイト列を組み立てる(端点a);
    }
    let (色0, 色1) = 詰めた値の大きい側を先にする(端点a, 端点b);
    let 四色表 = BC1の四色表::四色モードで生成する(色0, 色1);
    let mut 索引列 = [0; ブロック1つの画素数];
    for (索引, 画素) in 索引列.iter_mut().zip(画素一覧.iter()) {
        *索引 = 四色表.最も近い色の索引を返す(*画素);
    }
    バイト列へ詰める(色0, 色1, 索引列)
}

/// RGB565へ量子化した端点が一致したブロックは`色0 > 色1`を作れない。このときだけ3色モードを許容し、
/// 索引を全画素0に固定して色0を指す。索引1から3を1つも使わないため、透過の枝には入らない。
fn 単色のブロックのバイト列を組み立てる(端点: RGB565の端点色) -> [u8; 8] {
    バイト列へ詰める(端点, 端点, [0; ブロック1つの画素数])
}

/// `色0 > 色1`をここで強制する。この順序がGPUに4色モードを選ばせる唯一の合図である。
fn 詰めた値の大きい側を先にする(端点a: RGB565の端点色, 端点b: RGB565の端点色) -> (RGB565の端点色, RGB565の端点色) {
    if 端点a.詰めた値を返す() > 端点b.詰めた値を返す() {
        (端点a, 端点b)
    } else {
        (端点b, 端点a)
    }
}

/// 色は16ビット下位バイト先頭、索引は行ごとに1バイトで、行の先頭の画素が下位2ビットに来る。
fn バイト列へ詰める(色0: RGB565の端点色, 色1: RGB565の端点色, 索引列: [u8; ブロック1つの画素数]) -> [u8; 8] {
    let [色0の下位, 色0の上位] = 色0.詰めた値を返す().to_le_bytes();
    let [色1の下位, 色1の上位] = 色1.詰めた値を返す().to_le_bytes();
    let mut バイト列 = [色0の下位, 色0の上位, 色1の下位, 色1の上位, 0, 0, 0, 0];
    for (位置, 索引) in 索引列.into_iter().enumerate() {
        let 行 = 位置 / 索引1バイトあたりの画素数;
        let 列 = 位置 % 索引1バイトあたりの画素数;
        バイト列[4 + 行] |= 索引 << (2 * 列);
    }
    バイト列
}
