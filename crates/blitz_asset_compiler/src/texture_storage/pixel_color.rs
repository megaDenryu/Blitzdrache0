//! ブロックの画素色: ブロック圧縮の符号化が扱う、不透明度を除いた1画素の色である。
//! 端点の探索と索引の割当が同じ尺度で近さを測る必要があるため、その尺度をこの型が持つ。

use super::level_pixels::{緑の位置, 赤の位置, 青の位置};

/// 赤・緑・青の8ビット成分。BC1は不透明度を運ばないため持たない。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ブロックの画素色 {
    pub 赤: u8,
    pub 緑: u8,
    pub 青: u8,
}

impl ブロックの画素色 {
    /// 1画素4バイトの並びから色の3成分だけを取り出す。
    pub fn 画素の4バイトから生成する(画素: [u8; 4]) -> Self {
        Self {
            赤: 画素[赤の位置],
            緑: 画素[緑の位置],
            青: 画素[青の位置],
        }
    }

    /// 成分ごとの差の二乗和。差は最大255であるため3成分の和は32ビットに必ず収まる。
    pub fn 相手までの二乗距離を返す(self, 相手: Self) -> u32 {
        成分の二乗差を求める(self.赤, 相手.赤) + 成分の二乗差を求める(self.緑, 相手.緑) + 成分の二乗差を求める(self.青, 相手.青)
    }
}

fn 成分の二乗差を求める(左: u8, 右: u8) -> u32 {
    let 差 = u32::from(左.abs_diff(右));
    差 * 差
}
