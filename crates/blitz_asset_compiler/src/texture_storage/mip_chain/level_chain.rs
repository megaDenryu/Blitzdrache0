//! 原寸から1x1までの縮小段を並べる工程。段0が原寸であり、以降は前の段を縦横それぞれ半分に縮めた段が続く。
//! 段の数は、幅と高さの大きい方が1になるまで半分にした回数に1を足した数である。
//! 受け取るのは原寸の1段、返すのは段0から順に並べた全段である。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`

use blitz_engine::テクスチャデータ;

use crate::error::アセットコンパイルエラー;

use super::super::level_pixels::縮小段の画素の読み出し口;
use super::half_reduction::srgbの色として縦横を半分に縮める;

pub fn srgbの色として縮小段の連なりを作る(
    原寸: &テクスチャデータ,
) -> Result<Vec<テクスチャデータ>, アセットコンパイルエラー> {
    // 原寸が1x1のときは1度も縮めないため、寸法と画素列の食い違いをここで先に拒む。
    縮小段の画素の読み出し口::生成する(原寸)?;
    let mut 全段 = Vec::new();
    let mut 現在の段 = 原寸.clone();
    while 現在の段.幅 > 1 || 現在の段.高さ > 1 {
        let 次の段 = srgbの色として縦横を半分に縮める(&現在の段)?;
        全段.push(現在の段);
        現在の段 = 次の段;
    }
    全段.push(現在の段);
    Ok(全段)
}
