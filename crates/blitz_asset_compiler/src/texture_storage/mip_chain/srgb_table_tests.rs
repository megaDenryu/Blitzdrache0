//! sRGBの固定表の検査。両端の値・単調性・符号値と線形値の往復が全ての符号値で元へ戻ることを固定する。
//! 表が単調増加であることは、線形値から符号値へ戻す最近傍の探索が二分探索で正しく働く前提でもある。

use super::srgb_linear_table::{srgbの符号値を線形値へ復号する, 線形値をsrgbの符号値へ符号化する};

#[test]
fn 固定表の両端は零と最大値() {
    assert_eq!(srgbの符号値を線形値へ復号する(0), 0);
    assert_eq!(srgbの符号値を線形値へ復号する(255), u16::MAX);
    assert_eq!(線形値をsrgbの符号値へ符号化する(0), 0);
    assert_eq!(線形値をsrgbの符号値へ符号化する(u16::MAX), 255);
}

/// 表の中間の4点をsRGBの伝達関数の独立計算(round(65535 * f(c / 255)))の値で直に固定する。
/// 往復・単調・自己参照の検査は「表と整合する別の表」への差し替えを捕まえられないため、曲線そのものはこの直固定だけが守る。
#[test]
fn 固定表の中間の値はsrgbの曲線と一致する() {
    assert_eq!(srgbの符号値を線形値へ復号する(1), 20);
    assert_eq!(srgbの符号値を線形値へ復号する(64), 3360);
    assert_eq!(srgbの符号値を線形値へ復号する(128), 14146);
    assert_eq!(srgbの符号値を線形値へ復号する(200), 37852);
}

#[test]
fn 固定表は単調に増える() {
    for 符号値 in 0..255u8 {
        assert!(srgbの符号値を線形値へ復号する(符号値) < srgbの符号値を線形値へ復号する(符号値 + 1));
    }
}

#[test]
fn 符号値と線形値の往復は全ての符号値で元へ戻る() {
    for 符号値 in 0..=255u8 {
        assert_eq!(線形値をsrgbの符号値へ符号化する(srgbの符号値を線形値へ復号する(符号値)), 符号値);
    }
}
