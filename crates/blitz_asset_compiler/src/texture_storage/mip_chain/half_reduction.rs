//! 1つの縮小段から次の段を作る工程。縦横をそれぞれ半分にし、対応する2x2の4画素を平均する。
//! sRGBの色は固定表で線形値へ直してから平均し、最も近い符号値へ戻す(符号値のまま平均すると暗い側へ沈む)。
//! 不透明度は線形の量であるため符号値のまま平均する。平均は全て整数であり、浮動小数の丸めを1つも含まない。
//!
//! 奇数の寸法は切り捨てで半分にするため、末尾の1行・1列は次の段へ寄与しない。
//! 寸法が1の軸は1のまま残り、その軸の2つの標本は読み出し口の丸めによって同じ画素になる。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`

use blitz_engine::テクスチャデータ;

use crate::error::アセットコンパイルエラー;

use super::super::level_pixels::{
    不透明度の位置, 寸法を添字の型へ広げる, 緑の位置, 縮小段の画素の読み出し口, 赤の位置, 青の位置
};
use super::srgb_linear_table::{srgbの符号値を線形値へ復号する, 線形値をsrgbの符号値へ符号化する};

pub fn srgbの色として縦横を半分に縮める(
    段: &テクスチャデータ,
) -> Result<テクスチャデータ, アセットコンパイルエラー> {
    let 読み出し口 = 縮小段の画素の読み出し口::生成する(段)?;
    let 次の幅 = 半分にする(段.幅);
    let 次の高さ = 半分にする(段.高さ);
    let 横の数 = 寸法を添字の型へ広げる(次の幅)?;
    let 縦の数 = 寸法を添字の型へ広げる(次の高さ)?;
    let mut rgba8 = Vec::with_capacity(横の数 * 縦の数 * 4);
    for 縦 in 0..縦の数 {
        for 横 in 0..横の数 {
            rgba8.extend_from_slice(&四画素の平均を求める(&読み出し口, 横 * 2, 縦 * 2));
        }
    }
    Ok(テクスチャデータ {
        幅: 次の幅,
        高さ: 次の高さ,
        rgba8,
    })
}

/// 1は1のまま残す。零の寸法は読み出し口の生成が先に拒むためここには来ない。
fn 半分にする(寸法: u32) -> u32 {
    (寸法 / 2).max(1)
}

fn 四画素の平均を求める(読み出し口: &縮小段の画素の読み出し口<'_>, 左端: usize, 上端: usize) -> [u8; 4] {
    let 画素一覧 = [
        読み出し口.端で丸めて画素を読む(左端, 上端),
        読み出し口.端で丸めて画素を読む(左端 + 1, 上端),
        読み出し口.端で丸めて画素を読む(左端, 上端 + 1),
        読み出し口.端で丸めて画素を読む(左端 + 1, 上端 + 1),
    ];
    [
        srgbの成分を線形で平均する(&画素一覧, 赤の位置),
        srgbの成分を線形で平均する(&画素一覧, 緑の位置),
        srgbの成分を線形で平均する(&画素一覧, 青の位置),
        線形の成分をそのまま平均する(&画素一覧, 不透明度の位置),
    ]
}

fn srgbの成分を線形で平均する(画素一覧: &[[u8; 4]; 4], 成分の位置: usize) -> u8 {
    let 合計: u32 = 画素一覧
        .iter()
        .map(|画素| u32::from(srgbの符号値を線形値へ復号する(画素[成分の位置])))
        .sum();
    線形値をsrgbの符号値へ符号化する(線形値へ狭める(四捨五入して4で割る(合計)))
}

fn 線形の成分をそのまま平均する(画素一覧: &[[u8; 4]; 4], 成分の位置: usize) -> u8 {
    let 合計: u32 = 画素一覧.iter().map(|画素| u32::from(画素[成分の位置])).sum();
    let 平均 = 四捨五入して4で割る(合計);
    u8::try_from(平均).unwrap_or_else(|_| panic!("不透明度の平均が8ビットに収まらない: {平均}"))
}

/// ちょうど中間にある値は大きい側へ寄せる。
fn 四捨五入して4で割る(合計: u32) -> u32 {
    (合計 + 2) / 4
}

fn 線形値へ狭める(平均: u32) -> u16 {
    u16::try_from(平均).unwrap_or_else(|_| panic!("線形値の平均が16ビットに収まらない: {平均}"))
}
