//! 縮小段の生成の検査。線形での平均、奇数の寸法と1画素の軸の端の扱い、段の連なりの寸法の並びを固定する。
//! sRGBの固定表そのものの検査は隣の`srgb_table_tests`が持つ。

#![allow(clippy::unwrap_used)]

use blitz_engine::テクスチャデータ;

use super::half_reduction::srgbの色として縦横を半分に縮める;
use super::level_chain::srgbの色として縮小段の連なりを作る;
use super::srgb_linear_table::{srgbの符号値を線形値へ復号する, 線形値をsrgbの符号値へ符号化する};

fn 段を作る(幅: u32, 高さ: u32, 画素一覧: &[[u8; 4]]) -> テクスチャデータ {
    テクスチャデータ {
        幅,
        高さ,
        rgba8: 画素一覧.concat(),
    }
}

/// 白と黒の2x2は線形の平均が中央になるため、符号値のまま平均した128よりも明るい値になる。
#[test]
fn 黒と白の平均は線形の中央へ行く() {
    let 段 = 段を作る(2, 2, &[[0, 0, 0, 255], [255, 255, 255, 255], [255, 255, 255, 255], [0, 0, 0, 255]]);
    let 縮めた段 = srgbの色として縦横を半分に縮める(&段).unwrap();
    assert_eq!(縮めた段.幅, 1);
    assert_eq!(縮めた段.高さ, 1);
    let 期待 = 線形値をsrgbの符号値へ符号化する(u16::try_from((u32::from(u16::MAX) + 2) / 4 * 2).unwrap());
    assert_eq!(縮めた段.rgba8[0], 期待);
    assert!(縮めた段.rgba8[0] > 128, "符号値のまま平均した値より明るくならなかった");
}

/// 黒2つと中間の明るさ2つの平均は、固定表が返す線形値のちょうど半分になる。
/// 符号値に比例する値で固定表を代用すると別の符号値が出るため、この検査が曲線そのものを固定する。
#[test]
fn 中間の明るさの平均は固定表の線形値に従う() {
    let 中間 = [128, 128, 128, 255];
    let 段 = 段を作る(2, 2, &[[0, 0, 0, 255], [0, 0, 0, 255], 中間, 中間]);
    let 縮めた段 = srgbの色として縦横を半分に縮める(&段).unwrap();
    assert_eq!(
        縮めた段.rgba8[0],
        線形値をsrgbの符号値へ符号化する(srgbの符号値を線形値へ復号する(128) / 2)
    );
}

#[test]
fn 不透明度は符号値のまま平均する() {
    let 段 = 段を作る(2, 2, &[[0, 0, 0, 0], [0, 0, 0, 100], [0, 0, 0, 100], [0, 0, 0, 102]]);
    let 縮めた段 = srgbの色として縦横を半分に縮める(&段).unwrap();
    assert_eq!(縮めた段.rgba8[3], 76);
}

/// 奇数の幅は切り捨てで半分になり、末尾の1列は次の段へ寄与しない。
#[test]
fn 奇数の幅は末尾の列を落とす() {
    let 段 = 段を作る(3, 1, &[[0, 0, 0, 255], [0, 0, 0, 255], [255, 255, 255, 255]]);
    let 縮めた段 = srgbの色として縦横を半分に縮める(&段).unwrap();
    assert_eq!((縮めた段.幅, 縮めた段.高さ), (1, 1));
    assert_eq!(縮めた段.rgba8[0], 0);
}

/// 幅が1の軸は1のまま残り、2つの標本が端の丸めによって同じ画素になる。
#[test]
fn 幅が1の段は高さだけが縮む() {
    let 段 = 段を作る(1, 2, &[[0, 0, 0, 255], [255, 255, 255, 255]]);
    let 縮めた段 = srgbの色として縦横を半分に縮める(&段).unwrap();
    assert_eq!((縮めた段.幅, 縮めた段.高さ), (1, 1));
    let 期待 = 線形値をsrgbの符号値へ符号化する(u16::try_from((u32::from(u16::MAX) + 2) / 4 * 2).unwrap());
    assert_eq!(縮めた段.rgba8[0], 期待);
}

#[test]
fn 連なりの寸法は1x1まで並ぶ() {
    let 段 = テクスチャデータ {
        幅: 8,
        高さ: 2,
        rgba8: vec![64; 8 * 2 * 4],
    };
    let 全段 = srgbの色として縮小段の連なりを作る(&段).unwrap();
    let 寸法一覧: Vec<(u32, u32)> = 全段.iter().map(|段| (段.幅, 段.高さ)).collect();
    assert_eq!(寸法一覧, vec![(8, 2), (4, 1), (2, 1), (1, 1)]);
}

#[test]
fn 一様な段は縮めても同じ色のまま() {
    let 段 = テクスチャデータ {
        幅: 4,
        高さ: 4,
        rgba8: [200, 100, 50, 255].repeat(16),
    };
    let 全段 = srgbの色として縮小段の連なりを作る(&段).unwrap();
    for 各段 in &全段 {
        assert_eq!(各段.rgba8[0..4], [200, 100, 50, 255]);
    }
}
