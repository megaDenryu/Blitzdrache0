//! テクスチャ格納方針と材質テクスチャ役割。方針はその1回のコンパイルで焼くテクスチャの格納形式の選び方であり、
//! 役割は材質の中でそのテクスチャが何を表しているかである。どの役割をどの格納形式で焼くかは、この2つの組から決まる。
//!
//! 方針をコンパイルの入力にするのは、どのテクスチャを圧縮するかが絵の判断であってコンパイラの判断ではないためである。
//! 既定の`全てRGBA8`を当てはめるのはコンパイルの入口の引数解析の1箇所だけであり、この層の関数は方針を必須の引数で受け取る。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`「判断i」

use blitz_engine::texture_storage::テクスチャ格納形式;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum テクスチャ格納方針 {
    全てRGBA8,                  // 非圧縮のRGBA8で焼く。版4までと同じバイト列になる
    ベースカラーのブロック圧縮, // ベースカラーだけをBC1で焼き、他はRGBA8のまま残す
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 材質テクスチャ役割 {
    ベースカラー,
    金属粗さ,
    法線マップ,
}

impl テクスチャ格納方針 {
    /// 役割ごとに焼く格納形式を返す。法線と金属粗さをブロック圧縮の対象にしないのは、
    /// 法線が第3成分の再構成をシェーダーへ要求し、金属粗さが独立に動く2成分をBC1の1本の線分へ載せられないためである。
    pub fn 役割に割り当てる格納形式を返す(self, 役割: 材質テクスチャ役割) -> テクスチャ格納形式 {
        match (self, 役割) {
            (Self::ベースカラーのブロック圧縮, 材質テクスチャ役割::ベースカラー) => テクスチャ格納形式::BC1,
            (Self::全てRGBA8, _) | (Self::ベースカラーのブロック圧縮, 材質テクスチャ役割::金属粗さ | 材質テクスチャ役割::法線マップ) => {
                テクスチャ格納形式::RGBA8
            }
        }
    }
}
