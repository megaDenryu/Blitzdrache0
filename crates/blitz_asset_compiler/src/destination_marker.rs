//! 高さ格子と目印の原型から、目的地の目印を立てた地形チャンク1つ分の実行時シーンを焼く。
//! 地面の焼き方は地形の世界の工程をそのまま呼び、この工程が足すのは目印を地表へ据えることだけである。
//!
//! 目印をチャンクの側へ焼くのは、目印の高さがそのチャンクの高さ格子からしか求まらないためであり、
//! 目印がその場所のチャンクと一緒に読み込まれて一緒に解除されるためでもある。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「第1段階の定義」の項目10

mod scene;

use blitz_engine::{アセットID, カタログ, シーンを実行時形式へ格納する, チャンク座標};

use crate::compile::{コンパイル済みシーン, メタデータを集計する};
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子を読み込む;
use crate::texture_storage::テクスチャ格納方針;

/// 目印1本を、そのチャンクのどこへ据えるかの指定。高さは持たない。据える工程が高さ格子から地表高さを求めるためである。
pub struct 目印の据え付け {
    pub 原型id: アセットID,
    pub チャンク原点からの東メートル: f32,
    pub チャンク原点からの南メートル: f32,
}

pub fn 目印つき地形チャンクをコンパイルする(
    カタログ: &カタログ,
    id: &アセットID,
    所有チャンク: チャンク座標,
    目印一覧: &[目印の据え付け],
    方針: テクスチャ格納方針,
) -> Result<コンパイル済みシーン, アセットコンパイルエラー> {
    let パス = カタログ
        .パスを参照する(id)
        .ok_or_else(|| アセットコンパイルエラー::カタログ未登録(id.clone()))?;
    let 格子 = 高さ格子を読み込む(パス)?;
    let シーン = scene::目印つきのシーンを組み立てる(カタログ, &格子, 所有チャンク, パス.to_path_buf(), 目印一覧, 方針)?;
    let メタデータ = メタデータを集計する(&シーン)?;
    let 実行時バイト列 = シーンを実行時形式へ格納する(&シーン)?;
    Ok(コンパイル済みシーン {
        実行時バイト列,
        ソース依存一覧: シーン.参照ファイル一覧,
        メタデータ,
    })
}
