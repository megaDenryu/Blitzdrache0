//! 建物の静的物理形状の組み手の試験。担当するのは、据えた順が子形状識別子になること、
//! 据えた配置が直方体へ効くこと、同じ綴りの建物を2棟取り込めないことである。
//!
//! 配置表を手で作らず展開器から得るのは、据えた順という番号の由来が展開の側にあり、
//! 手で並べた表で試験すると、展開が順を変えたときにこの試験が気づかないためである。

#![allow(clippy::unwrap_used)]

use blitz_assembly::{
    展開器, 組み立て手順, 部品ID, 部品ごとの配置表, 部品の境界箱, 部品カタログ組み立て器, 部品定義
};
use blitz_engine::static_shape::衝突対象の安定識別子;
use blitz_engine::個体配置;

use super::building_builder::建物の静的物理形状の組み手;
use super::part_box_table::部品ごとの境界箱の表;

fn 壁の識別子() -> 部品ID {
    部品ID::生成する("壁").unwrap()
}

/// 接合点を持たない部品1件だけのカタログ。対の相手を要求する接合点が無いため組み上げが通る。
fn 壁1件を据えた配置表(根の配置: 個体配置) -> 部品ごとの配置表 {
    let mut 組み立て器 = 部品カタログ組み立て器::空から始める();
    組み立て器.部品を1つ積む(壁の識別子(), 部品定義::生成する(Vec::new()).unwrap()).unwrap();
    let 展開器 = 展開器::カタログを持たせて生成する(組み立て器.組み上げる().unwrap());
    let 手順 = 組み立て手順::根と指示から生成する(壁の識別子(), Vec::new());
    展開器.手順を展開する(&手順, 根の配置).unwrap()
}

fn 壁だけの境界箱の表() -> 部品ごとの境界箱の表 {
    let 箱 = 部品の境界箱::最小と最大から生成する([-1.0, 0.0, -0.25], [1.0, 3.0, 0.25]).unwrap();
    部品ごとの境界箱の表::一件だけの表を作る(壁の識別子(), 箱)
}

fn 東へ寄せた配置() -> 個体配置 {
    個体配置::生成する([7.0, 1.0, -2.0], [0.0, 0.0, 0.0, 1.0], [1.0; 3]).unwrap()
}

#[test]
fn 据えた順が子形状識別子になり配置が直方体へ効く() {
    let mut 組み手 = 建物の静的物理形状の組み手::境界箱の表を持たせて始める(壁だけの境界箱の表());
    組み手
        .建物を1棟取り込む(衝突対象の安定識別子::生成する("酒場").unwrap(), &壁1件を据えた配置表(東へ寄せた配置()))
        .unwrap();
    let 形状 = 組み手.組み上げる().unwrap();
    let 対象 = &形状.衝突対象一覧()[0];
    assert_eq!(対象.安定識別子().綴り(), "酒場");
    let 子形状 = 対象.子形状一覧()[0];
    assert_eq!(子形状.識別子().番号を返す(), 0);
    let 中心 = 子形状.直方体().中心();
    assert_eq!((中心.x().値(), 中心.y().値(), 中心.z().値()), (7.0, 2.5, -2.0));
    let 半分 = 子形状.直方体().軸ごとの半分の長さ();
    assert_eq!((半分.x().値(), 半分.y().値(), 半分.z().値()), (1.0, 1.5, 0.25));
}

#[test]
fn 綴りの違う2棟は同じチャンクへ載る() {
    let mut 組み手 = 建物の静的物理形状の組み手::境界箱の表を持たせて始める(壁だけの境界箱の表());
    for 綴り in ["酒場", "宿屋"] {
        組み手
            .建物を1棟取り込む(衝突対象の安定識別子::生成する(綴り).unwrap(), &壁1件を据えた配置表(東へ寄せた配置()))
            .unwrap();
    }
    let 形状 = 組み手.組み上げる().unwrap();
    assert_eq!((形状.衝突対象数(), 形状.子形状の総数()), (2, 2));
}

#[test]
fn 同じ綴りの2棟は組み上げで拒む() {
    let mut 組み手 = 建物の静的物理形状の組み手::境界箱の表を持たせて始める(壁だけの境界箱の表());
    for _ in 0..2 {
        組み手
            .建物を1棟取り込む(衝突対象の安定識別子::生成する("酒場").unwrap(), &壁1件を据えた配置表(東へ寄せた配置()))
            .unwrap();
    }
    assert!(組み手.組み上げる().is_err());
}

#[test]
fn 表に無い部品を据えた建物は拒む() {
    let 箱 = 部品の境界箱::最小と最大から生成する([0.0; 3], [1.0; 3]).unwrap();
    let 表 = 部品ごとの境界箱の表::一件だけの表を作る(部品ID::生成する("屋根").unwrap(), 箱);
    let mut 組み手 = 建物の静的物理形状の組み手::境界箱の表を持たせて始める(表);
    let 結果 = 組み手.建物を1棟取り込む(衝突対象の安定識別子::生成する("酒場").unwrap(), &壁1件を据えた配置表(東へ寄せた配置()));
    assert!(結果.is_err());
}
