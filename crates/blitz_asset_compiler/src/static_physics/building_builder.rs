//! 建物の静的物理形状の組み手: 展開した建物を1棟ずつ取り込み、チャンク1つ分の静的物理形状へ組み上げる型。
//!
//! 組み手を通すのは、安定識別子が1つのチャンクの中で重ならないという不変条件を、全棟を取り込み終えるまで
//! 検査できないためである。1棟ずつ読んでいる途中では判定できない。作れるのは`組み上げる`だけである。
//!
//! 子形状識別子に据えた順の添字をそのまま使うのは、その番号が「建物のどの部品か」を制作時のデータへ辿る手がかりに
//! なるためである。展開は同じ入力から同じ順で部品を据えるため、焼き直しても番号は変わらない。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断9: 複合形状は子形状を束ねて1つの衝突対象にする」

use blitz_assembly::部品ごとの配置表;
use blitz_engine::static_shape::{
    チャンクの静的物理形状, 子形状識別子, 衝突対象の子形状, 衝突対象の安定識別子, 静的な衝突対象
};

use super::error::静的物理形状のコンパイルエラー;
use super::part_box_table::部品ごとの境界箱の表;

/// 展開した建物を1棟ずつ取り込み、チャンク1つ分の静的物理形状へ組み上げるビルダー。
pub(crate) struct 建物の静的物理形状の組み手 {
    境界箱の表: 部品ごとの境界箱の表,
    衝突対象一覧: Vec<静的な衝突対象>,
}

impl 建物の静的物理形状の組み手 {
    /// 部品ごとの境界箱の表を持たせて、1棟も取り込んでいない状態から始める。
    pub(crate) fn 境界箱の表を持たせて始める(境界箱の表: 部品ごとの境界箱の表) -> Self {
        Self {
            境界箱の表,
            衝突対象一覧: Vec::new(),
        }
    }

    /// 1棟の配置表を、据えた順の子形状を持つ静的な衝突対象へ写して溜める。
    pub(crate) fn 建物を1棟取り込む(
        &mut self,
        安定識別子: 衝突対象の安定識別子,
        配置表: &部品ごとの配置表,
    ) -> Result<(), 静的物理形状のコンパイルエラー> {
        let mut 子形状一覧 = Vec::with_capacity(配置表.配置の総数());
        for (添字, 据えた) in 配置表.据えた順().iter().enumerate() {
            let 番号 = u32::try_from(添字).map_err(|_| {
                静的物理形状のコンパイルエラー::子形状の番号が32ビットに収まらない {
                    建物の綴り: 安定識別子.綴り().to_string(),
                }
            })?;
            let 直方体 = self
                .境界箱の表
                .識別子で参照する(据えた.識別子())?
                .配置で任意姿勢の直方体へ写す(&据えた.配置())
                .map_err(|原因| 静的物理形状のコンパイルエラー::直方体へ写せない {
                    建物の綴り: 安定識別子.綴り().to_string(),
                    部品の綴り: 据えた.識別子().綴り().to_string(),
                    原因: 原因.to_string(),
                })?;
            子形状一覧.push(衝突対象の子形状::識別子と直方体から生成する(
                子形状識別子::番号から生成する(番号),
                直方体,
            ));
        }
        self.衝突対象一覧.push(静的な衝突対象::安定識別子と子形状一覧から生成する(
            安定識別子,
            子形状一覧,
        )?);
        Ok(())
    }

    /// 溜めた衝突対象をチャンクの静的物理形状にする。安定識別子の重複はここで初めて判定できる。
    pub(crate) fn 組み上げる(self) -> Result<チャンクの静的物理形状, 静的物理形状のコンパイルエラー> {
        Ok(チャンクの静的物理形状::衝突対象一覧から生成する(
            self.衝突対象一覧,
        )?)
    }
}
