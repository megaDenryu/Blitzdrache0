//! 建物の静的物理形状を焼く工程が拒む理由。
//!
//! 部品の綴りと建物の綴りを文面へ載せるのは、この誤りの読み手が建物を置いたエディターの利用者であり、
//! どの建物のどの部品で止まったかが分からなければ直しようがないためである。

use blitz_engine::static_shape::静的物理形状エラー;

/// 建物の静的物理形状を焼く工程が拒む理由。
#[derive(Debug, thiserror::Error)]
pub enum 静的物理形状のコンパイルエラー {
    /// 部品のglTFを開けないか、そのアクセサ宣言から境界箱を読めない。
    #[error("部品{部品の綴り}の境界箱を読めない: {原因}")]
    部品の境界箱を読めない { 部品の綴り: String, 原因: String },
    /// 展開が据えた部品の境界箱が、部品一式から読んだ表に無い。
    #[error("据えた部品{部品の綴り}の境界箱が宣言に無い")]
    据えた部品の境界箱が無い { 部品の綴り: String },
    /// 部品の境界箱と据えた配置から、任意姿勢の直方体を作れない。
    #[error("建物{建物の綴り}の部品{部品の綴り}を直方体へ写せない: {原因}")]
    直方体へ写せない {
        建物の綴り: String, 部品の綴り: String, 原因: String
    },
    /// 据えた部品の件数が子形状識別子の32ビットの番号に収まらない。
    #[error("建物{建物の綴り}が据えた部品の数が32ビットの番号に収まらない")]
    子形状の番号が32ビットに収まらない { 建物の綴り: String },
    /// 焼き上げた値が`blitz_engine`の静的物理形状の不変条件を満たさない。
    #[error("静的物理形状が条件を満たさない: {0}")]
    静的物理形状が不正(#[from] 静的物理形状エラー),
}
