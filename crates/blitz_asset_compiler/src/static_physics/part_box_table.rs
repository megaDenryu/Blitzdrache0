//! 部品ごとの境界箱の表: 宣言された部品の実体から読んだ境界箱を、部品の識別子で引ける形で持つ型。
//!
//! 建物1棟ごとに読み直さないのは、1つのチャンクが同じ部品を何十回も据えるためである。境界箱はglTFのアクセサの
//! 宣言だけから読めてバッファ実体を読まないが、それでも据えた件数ぶんファイルを開くのは無駄である。
//!
//! 部品カタログが境界箱を持たないため、この表を別に作る。カタログが持つのは接合点であり、
//! 箱は配置の計算に要らない(参照: `_doc/設計/部品カタログと接合点.md`「部品カタログと展開器」)。

use blitz_assembly::{部品ID, 部品の境界箱};

use super::error::静的物理形状のコンパイルエラー;
use crate::assembly_parts::組み立てに使う部品一式;
use crate::loader::部品のglTFのファイル;

struct 部品と境界箱の対 {
    識別子: 部品ID,
    境界箱: 部品の境界箱,
}

pub(crate) struct 部品ごとの境界箱の表 {
    一覧: Vec<部品と境界箱の対>,
}

impl 部品ごとの境界箱の表 {
    pub(crate) fn 部品一式から読む(
        部品一式: &組み立てに使う部品一式
    ) -> Result<Self, 静的物理形状のコンパイルエラー> {
        let mut 一覧 = Vec::new();
        for (識別子, 置き場) in 部品一式.部品とソースの置き場を数え上げる() {
            let 境界箱 = 部品のglTFのファイル::生成する(置き場).境界箱を読み取る().map_err(|原因| {
                静的物理形状のコンパイルエラー::部品の境界箱を読めない {
                    部品の綴り: 識別子.綴り().to_string(),
                    原因: 原因.to_string(),
                }
            })?;
            一覧.push(部品と境界箱の対 {
                識別子: 識別子.clone(),
                境界箱,
            });
        }
        Ok(Self { 一覧 })
    }

    /// 部品の実体を読まずに一件だけの表を作る。ソースの置き場を用意せずに組み手の計算だけを見る試験が使う。
    #[cfg(test)]
    pub(crate) fn 一件だけの表を作る(識別子: 部品ID, 境界箱: 部品の境界箱) -> Self {
        Self {
            一覧: vec![部品と境界箱の対 { 識別子, 境界箱 }],
        }
    }

    pub(crate) fn 識別子で引く(&self, 識別子: &部品ID) -> Result<部品の境界箱, 静的物理形状のコンパイルエラー> {
        self.一覧.iter().find(|対| &対.識別子 == 識別子).map(|対| 対.境界箱).ok_or_else(|| {
            静的物理形状のコンパイルエラー::据えた部品の境界箱が無い {
                部品の綴り: 識別子.綴り().to_string(),
            }
        })
    }
}
