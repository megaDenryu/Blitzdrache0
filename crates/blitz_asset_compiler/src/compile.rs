//! 検証済みシーンから実行時バイト列、依存関係、容量メタデータを作る。
//! glTFで書かれた1つのシーンを焼く工程は`source_scene`が持つ。
//!
//! `置いた個体の数`はメタデータの個体数と別の地点で数えた値であり、2つの食い違いが群の描画対象への載せ漏れを表す。

mod source_scene;

use std::path::PathBuf;

use blitz_engine::texture_storage::格納済みテクスチャ;
use blitz_engine::{
    アセットメタデータ, シーンを実行時形式へ格納する, シーンデータ, マテリアルデータ, 描画形状
};

use crate::assembled_scene::組み立てたシーン;
use crate::placed_instance_count::{種類ごとの置いた個体の数, 置いた個体の数};
use crate::アセットコンパイルエラー;

pub struct コンパイル済みシーン {
    pub 実行時バイト列: Vec<u8>,
    pub ソース依存一覧: Vec<PathBuf>,
    pub メタデータ: アセットメタデータ,
    pub 置いた個体の数: 置いた個体の数, // 組み立ての工程が実際に置いた個体の数
    pub 種類ごとの内訳: 種類ごとの置いた個体の数, // 散らした種類ごとの内訳。散らさない対象では空
}

impl コンパイル済みシーン {
    /// 組み上がったシーンを実行時形式へ落とし、依存とメタデータを添えて1件へまとめる。
    /// 世界の種類ごとの焼く工程がこの1つの口へ合流するため、集計と格納の順序も1箇所で決まる。
    pub(crate) fn 組み立てたシーンから焼く(組み立て: 組み立てたシーン) -> Result<Self, アセットコンパイルエラー> {
        let メタデータ = メタデータを集計する(&組み立て.シーン)?;
        let 実行時バイト列 = シーンを実行時形式へ格納する(&組み立て.シーン)?;
        Ok(Self {
            実行時バイト列,
            ソース依存一覧: 組み立て.シーン.参照ファイル一覧,
            メタデータ,
            置いた個体の数: 組み立て.置いた個体の数,
            種類ごとの内訳: 組み立て.種類ごとの内訳,
        })
    }
}

fn メタデータを集計する(シーン: &シーンデータ) -> Result<アセットメタデータ, アセットコンパイルエラー> {
    let mut 結果 = アセットメタデータ::default();
    for 対象 in シーン.描画対象一覧() {
        // 全段を読込時にGPUへ載せるため、地形LODメッシュ群は全段を数える(参照: `_doc/設計/地形とカメラ相対描画.md`「LOD」)。
        for メッシュ in 対象.形状().全メッシュ() {
            加算する(&mut 結果.頂点数, メッシュ.頂点一覧.len())?;
            加算する(&mut 結果.インデックス数, メッシュ.インデックス一覧.len())?;
        }
        if let 描画形状::インスタンス群(群) = 対象.形状() {
            加算する(&mut 結果.個体数, 群.個体数())?;
        }
        for 割当 in 対象.材質集合().割当一覧() {
            // テクスチャ格納バイト数は格納形式で数えた全段の合計であり、GPUへ載る実バイト数と一致する。
            for テクスチャ in 材質が持つテクスチャ一覧(&割当.マテリアル) {
                for 段 in テクスチャ.段ごとのバイト列を返す() {
                    加算する(&mut 結果.テクスチャ格納バイト数, 段.len())?;
                }
            }
        }
    }
    Ok(結果)
}

/// シーンとともに焼かれるテクスチャ。地表の層の重ね合わせが持つのは重みだけであり、層のタイルは世界に1つ置く
/// 共有アセットのため、チャンクの容量メタデータには数えない。
fn 材質が持つテクスチャ一覧(マテリアル: &マテリアルデータ) -> Vec<&格納済みテクスチャ> {
    match マテリアル {
        マテリアルデータ::金属粗さPBR(材質) => [&材質.ベースカラー, &材質.金属粗さ, &材質.法線マップ].into_iter().flatten().collect(),
        マテリアルデータ::地表の層の重ね合わせ(材質) => vec![材質.重みテクスチャ()],
    }
}

fn 加算する(合計: &mut u64, 件数: usize) -> Result<(), アセットコンパイルエラー> {
    let 件数 = u64::try_from(件数).map_err(|_| blitz_engine::アセット実行時形式エラー::長さ表現不能)?;
    *合計 = 合計.checked_add(件数).ok_or(blitz_engine::アセット実行時形式エラー::長さ表現不能)?;
    Ok(())
}
