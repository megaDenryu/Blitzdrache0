//! 検証済みシーンから実行時バイト列、依存関係、容量メタデータを作る。

use std::path::PathBuf;

use blitz_engine::{
    アセットID, アセットメタデータ, カタログ, シーンを実行時形式へ格納する, チャンク座標, マテリアルデータ, 描画形状
};

use crate::{アセットコンパイルエラー, ソースシーンを読み込む};

pub struct コンパイル済みシーン {
    pub 実行時バイト列: Vec<u8>,
    pub ソース依存一覧: Vec<PathBuf>,
    pub メタデータ: アセットメタデータ,
}

pub fn ソースシーンをコンパイルする(
    カタログ: &カタログ,
    id: &アセットID,
    所有チャンク: チャンク座標,
) -> Result<コンパイル済みシーン, アセットコンパイルエラー> {
    let シーン = ソースシーンを読み込む(カタログ, id, 所有チャンク)?;
    let メタデータ = メタデータを集計する(&シーン)?;
    let 実行時バイト列 = シーンを実行時形式へ格納する(&シーン)?;
    Ok(コンパイル済みシーン {
        実行時バイト列,
        ソース依存一覧: シーン.参照ファイル一覧,
        メタデータ,
    })
}

pub(crate) fn メタデータを集計する(
    シーン: &blitz_engine::シーンデータ,
) -> Result<アセットメタデータ, アセットコンパイルエラー> {
    let mut 結果 = アセットメタデータ::default();
    for 対象 in シーン.描画対象一覧() {
        // 全段を読込時にGPUへ載せるため、地形LODメッシュ群は全段を数える(参照: `_doc/設計/地形とカメラ相対描画.md`「LOD」)。
        for メッシュ in 対象.形状().全メッシュ() {
            加算する(&mut 結果.頂点数, メッシュ.頂点一覧.len())?;
            加算する(&mut 結果.インデックス数, メッシュ.インデックス一覧.len())?;
        }
        if let 描画形状::インスタンス群(群) = 対象.形状() {
            加算する(&mut 結果.個体数, 群.個体数())?;
        }
        let マテリアルデータ::金属粗さPBR(材質) = 対象.マテリアル();
        for テクスチャ in [&材質.ベースカラー, &材質.金属粗さ, &材質.法線マップ].into_iter().flatten() {
            加算する(&mut 結果.テクスチャバイト数, テクスチャ.rgba8.len())?;
        }
    }
    Ok(結果)
}

fn 加算する(合計: &mut u64, 件数: usize) -> Result<(), アセットコンパイルエラー> {
    let 件数 = u64::try_from(件数).map_err(|_| blitz_engine::アセット実行時形式エラー::長さ表現不能)?;
    *合計 = 合計.checked_add(件数).ok_or(blitz_engine::アセット実行時形式エラー::長さ表現不能)?;
    Ok(())
}
