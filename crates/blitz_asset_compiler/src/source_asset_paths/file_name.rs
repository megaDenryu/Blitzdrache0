//! ソースアセットのファイル名: 1つのディレクトリの直下に置くソースアセット1件の名前を表す値オブジェクト。
//!
//! 相対パスと別の型にするのは、どちらも文字列であり、取り違えても型が通るためである。区切りを含む綴りを
//! ファイル名の位置へ渡すと、その名前のファイルを作れず、失敗が書き出しの段まで遅れて現れる。
//!
//! 検証を構築時に行うのは、綴りが不正でもパスを組むところまでは成功し、ファイルを開く段になって初めて
//! 「見つからない」で失敗するためである。失敗を生成の奥まで遅らせない。

use std::path::{Path, PathBuf};

use super::spelling;

#[repr(transparent)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ソースアセットのファイル名(&'static str);

impl ソースアセットのファイル名 {
    /// 綴りの表が`const`のまま書けるように`const fn`にする。破れは実行時の失敗でなくコンパイルの失敗として出る。
    ///
    /// 注意: 破れたときに`panic!`へ落ちるのは、この関数がコンパイル時の定数にしか適用されず、
    /// 破れが到達したらプログラムのバグだからである。破れの綴りは定数の定義位置がそのまま指す。
    pub const fn 生成する(綴り: &'static str) -> Self {
        if spelling::空か(綴り) {
            panic!("ソースアセットのファイル名が空である");
        }
        if spelling::斜線を含むか(綴り) || spelling::逆斜線を含むか(綴り) {
            panic!("ソースアセットのファイル名が区切りを含み、1つのディレクトリの直下を指していない");
        }
        if spelling::今の場所を指す綴りか(綴り) || spelling::連なる点を含むか(綴り) {
            panic!("ソースアセットのファイル名が場所を指す綴りであり、ファイルを1つも指していない");
        }
        if spelling::コロンを含むか(綴り) {
            panic!("ソースアセットのファイル名がコロンを含み、Windowsの連結で基準のディレクトリを置き換える");
        }
        Self(綴り)
    }

    /// 与えられたディレクトリの直下でこの名前が指すファイル。名前がパスへ組み上がる口はここだけである。
    pub fn ディレクトリの直下のファイル(self, ディレクトリ: &Path) -> PathBuf {
        ディレクトリ.join(self.0)
    }

    /// 人へ見せる綴りと、ファイル名を綴りでしか受け取れない口(ファイルの走査・書き出しの口)へ渡す綴り。
    /// パスを組む口ではない。パスは`ディレクトリの直下のファイル`が組む。
    pub fn 綴りを見せる(self) -> &'static str {
        self.0
    }
}
