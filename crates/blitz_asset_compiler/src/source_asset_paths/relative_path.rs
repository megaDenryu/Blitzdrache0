//! ソースアセットの相対パス: あるルートからの相対でソースアセット1件を指す綴りを表す値オブジェクト。
//!
//! 綴りを裸の`&str`で持ち回らないのは、宣言の一覧が安定IDと相対パスという同じ形の2つを並べて持ち、
//! 取り違えても型が通るためである。どのルートからの相対かはルートを持つ型が名乗り、この型は綴りだけを持つ。
//!
//! 検証を構築時に行うのは、ルートの外を指す綴りやディレクトリを指す綴りでもパスを組むところまでは成功し、
//! ファイルを開く段になって初めて失敗するためである。失敗を生成の奥まで遅らせない。

use std::path::{Path, PathBuf};

use super::file_name::ソースアセットのファイル名;
use super::spelling;

/// 相対パスの成分を区切る綴り。Windowsでも斜線で開けるため、綴りの正本は斜線だけで書く。
const 区切り: char = '/';

#[repr(transparent)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ソースアセットの相対パス(&'static str);

impl ソースアセットの相対パス {
    /// 宣言の表が`const`のまま書けるように`const fn`にする。破れは実行時の失敗でなくコンパイルの失敗として出る。
    ///
    /// 注意: 破れたときに`panic!`へ落ちるのは、この関数がコンパイル時の定数にしか適用されず、
    /// 破れが到達したらプログラムのバグだからである。破れの綴りは定数の定義位置がそのまま指す。
    pub const fn 生成する(綴り: &'static str) -> Self {
        if spelling::空か(綴り) {
            panic!("ソースアセットの相対パスが空である");
        }
        if spelling::逆斜線を含むか(綴り) {
            panic!("ソースアセットの相対パスが逆斜線を含む。綴りの正本は斜線だけで書く");
        }
        if spelling::斜線で始まるか(綴り) {
            panic!("ソースアセットの相対パスが斜線で始まり、ルートからの相対でなく場所そのものを指している");
        }
        if spelling::斜線で終わるか(綴り) {
            panic!("ソースアセットの相対パスが斜線で終わり、ファイルでなくディレクトリを指している");
        }
        if spelling::空の成分を含むか(綴り) {
            panic!("ソースアセットの相対パスが空の成分を含む");
        }
        if spelling::連なる点を含むか(綴り) {
            panic!("ソースアセットの相対パスがルートの外へ出る成分を含む");
        }
        if spelling::コロンを含むか(綴り) {
            panic!("ソースアセットの相対パスがコロンを含み、Windowsの連結で基準のディレクトリを置き換える");
        }
        Self(綴り)
    }

    /// この相対パスが指すファイルの名前。取得元の綴りをファイル名だけで組む口が、名前を別に持ち直さずに済む。
    pub fn 末尾のファイル名(self) -> ソースアセットのファイル名 {
        match self.0.rsplit_once(区切り) {
            Some((_, ファイル名)) => ソースアセットのファイル名::生成する(ファイル名),
            None => ソースアセットのファイル名::生成する(self.0),
        }
    }

    /// 与えられたルートの下でこの相対パスが指すファイル。綴りがパスへ組み上がる口はこことこの下の1つだけである。
    /// ルートの役割(本体のソースルートか外部のアセットリポジトリか)はルートを持つ型が名乗る。
    pub(crate) fn ルートの下のファイル(self, ルート: &Path) -> PathBuf {
        ルート.join(self.0)
    }

    /// 与えられたルートの下でこの相対パスが指すファイルを収めるディレクトリ。書き出す前に作る側が読む。
    /// 区切りを持たない綴りではルートそのものが収める場所になる。
    pub(crate) fn ルートの下の収める場所(self, ルート: &Path) -> PathBuf {
        match self.0.rsplit_once(区切り) {
            Some((ディレクトリ, _)) => ルート.join(ディレクトリ),
            None => ルート.to_path_buf(),
        }
    }

    /// 人へ見せる綴り。失敗の報せがこの口を通り、パスを組む口と使い分ける。
    pub fn 綴りを見せる(self) -> &'static str {
        self.0
    }
}
