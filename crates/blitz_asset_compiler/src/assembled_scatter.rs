//! 部品で組んだ個体を地面へ散らす工程。受け取るのは高さ格子と所有チャンクと散らす指定、
//! 返すのは部品の種類ごとの群の描画対象と、置いた個体の数である。
//!
//! **1個体が複数の部品の個体になる。** 木1本は幹と枝と葉房の10部品へ展開され、描画対象は部品の種類の数だけになる。
//! 本数が増えて伸びるのは群の中の配置列だけであり、描画対象の数は宣言した部品の種類の数を超えない。
//!
//! 根をどこへ置くかは原型を散らす工程と同じものを使う。密度場と傾きと出現の判定で根の配置列を作り、
//! その1件ずつを規則で展開して部品ごとに畳む。写しを持つと、同じ世界の木と岩が違う格子の上に乗る。
//!
//! **散らす工程を2段に分けているのは、描画対象番号が群を作る時点で決まるためである。** 何種類の群になるかは
//! 展開してみるまで分からないため、先に集約を作って種類の数を答え、呼び出し側が番号を配ってから群にする。
//! 参照: `_doc/設計/部品カタログと接合点.md`「段6: 散布の針葉樹を部品で組んだ木へ差し替える」

mod error;
mod expansion_run;
mod groups;

use blitz_assembly::部品ごとの配置の集約;
use blitz_engine::チャンク座標;

use crate::assembly_parts::組み立てに使う部品一式;
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子;
use crate::placement::{根の配置列を散らす, 部品で組む散布の指定, 配置の混合の通し番号};
use crate::scene_compiler::ソースアセットのコンパイル係;

pub use error::部品で組んだ散布のコンパイルエラー;
use expansion_run::部品で組む散布の展開係;
pub(crate) use groups::部品ごとの群一覧;

/// 散らして展開し終えた1つの種。部品の種類の数が決まっているため、呼び出し側はここで描画対象番号を配れる。
pub(crate) struct 散らした部品の集約 {
    部品一式: 組み立てに使う部品一式,
    集約: 部品ごとの配置の集約,
}

impl 散らした部品の集約 {
    /// この種が作る群の数。描画対象番号を配る件数であり、散らした本数ではない。
    pub(crate) fn 群の件数(&self) -> usize {
        self.集約.部品の種類数()
    }
}

impl ソースアセットのコンパイル係<'_> {
    /// 散らす種1つを走査して展開する。1体も置かない区画しか無いチャンクでは、群の件数が0の集約を返す。
    pub(crate) fn 部品で組む散布を展開する(
        &self,
        格子: &高さ格子,
        所有チャンク: チャンク座標,
        通し番号: 配置の混合の通し番号,
        指定: &部品で組む散布の指定,
    ) -> Result<散らした部品の集約, アセットコンパイルエラー> {
        let 根の配置一覧 = 根の配置列を散らす(格子, 所有チャンク, 通し番号, self.配置の種を貸す(), 指定.密度場の散布)?;
        let 部品一式 = 組み立てに使う部品一式::宣言から読み取る(self, &指定.部品の安定id一覧)?;
        let 集約 = 部品で組む散布の展開係::生成する(部品一式.カタログを組み上げる()?, 指定.種の起点)
            .根の配置列を展開する(&指定.規則, &根の配置一覧)?;
        Ok(散らした部品の集約 { 部品一式, 集約 })
    }

    /// 展開した集約を、部品の種類ごとの群にする。先頭の描画対象番号から1つずつ配る。
    pub(crate) fn 散らした部品の群を作る(
        &self,
        所有チャンク: チャンク座標,
        先頭の描画対象番号: u64,
        集約: &散らした部品の集約,
    ) -> Result<部品ごとの群一覧, アセットコンパイルエラー> {
        groups::集約から群を作る(self, 所有チャンク, 先頭の描画対象番号, &集約.部品一式, &集約.集約)
    }
}
