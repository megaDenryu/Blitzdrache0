/// 地形の描画対象番号。1つの高さ格子が1つの描画対象になるため常にこの値である。
const 地形描画対象番号: u64 = 0;

/// 同居する植生の描画対象番号。1つのチャンクが1つの群を持つため常にこの値である。
const 植生描画対象番号: u64 = 1;

/// 検収の地形の地面のベースカラー係数。既存の判定値がこの白い地面の上に立っているため動かさない。
const 検収の地面のベースカラー係数: [f32; 4] = [1.0, 1.0, 1.0, 1.0];

/// 草地のベースカラー係数の正本。遠景・固定物・エディターチャンクの3つの経路が同じ暗さの地面を焼くため、
/// 値をここ1箇所へ置いて各経路が参照する。検収の世界の白い地面のままでは、自動露出が画面のほとんどを占める
/// 地面へ合わせるため地面が白く飛び、起伏も固定物の影も読み取れない絵になる。
pub(crate) const 草地のベースカラー係数: [f32; 4] = [0.13, 0.19, 0.09, 1.0];

impl ソースアセットのコンパイル係<'_> {
    pub fn 地形チャンクをコンパイルする(
        &self,
        id: &アセットID,
        所有チャンク: チャンク座標,
        同居植生: Option<&同居植生の指定>,
    ) -> Result<コンパイル済みシーン, アセットコンパイルエラー> {
        let パス = self.安定idが指すソースのパスを参照する(id)?;
        let 格子 = 高さ格子を読み込む(パス)?;
        let 組み立て = self.地形のシーンを組み立てる(&格子, 所有チャンク, パス.to_path_buf(), 同居植生)?;
        コンパイル済みシーン::組み立てたシーンから焼く(組み立て)
    }

    pub(crate) fn 地形のシーンを組み立てる(
        &self,
        格子: &高さ格子,
        所有チャンク: チャンク座標,
        ソースパス: std::path::PathBuf,
        同居植生: Option<&同居植生の指定>,
    ) -> Result<組み立てたシーン, アセットコンパイルエラー> {
        let 地形 = ground_object::高さ格子から地面の描画対象を作る(
            格子,
            所有チャンク,
            地形描画対象番号,
            ground_object::地形の単色材質を作る(検収の地面のベースカラー係数),
        )?;
        let mut 参照ファイル一覧 = vec![ソースパス];
        let mut 残りの描画対象 = Vec::new();
        let mut 置いた個体の数 = 置いた個体の数::零();
        if let Some(指定) = 同居植生 {
            let 地表高さを求める = |x, z| ground_height::地表高さを求める(格子, x, z);
            let 群 = self.地形同居の群を作る(指定, 所有チャンク, 植生描画対象番号, 地表高さを求める)?;
            置いた個体の数 = 群.置いた個体の数;
            参照ファイル一覧.extend(群.参照ファイル一覧);
            残りの描画対象.push(群.描画対象);
        }
        let シーン = シーンデータ::生成する(地形, 残りの描画対象, 参照ファイル一覧, None, Vec::new());
        Ok(組み立てたシーン::置いた個体の数を添えて生成する(
            シーン,
            置いた個体の数,
        ))
    }
}
