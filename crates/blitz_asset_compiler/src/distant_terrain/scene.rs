//! 遠景メッシュ1枚を世界原点所有の通常シーンへ組み立てる。

use std::path::PathBuf;

use blitz_engine::{
    シーンデータ, チャンク座標, マテリアルデータ, メッシュデータ, 描画対象ID, 描画対象データ, 描画形状, 材質集合, 金属粗さPBRデータ
};

pub(super) fn 通常シーンを作る(メッシュ: メッシュデータ, 依存一覧: Vec<PathBuf>) -> シーンデータ {
    let 対象 = 描画対象データ::生成する(
        描画対象ID::生成する(0),
        チャンク座標::生成する(0, 0),
        crate::terrain::ground_object::単位変換を作る(),
        描画形状::通常メッシュ(メッシュ),
        材質集合::単一材質から生成する(材質を作る()),
    );
    シーンデータ::生成する(対象, Vec::new(), 依存一覧, None, Vec::new())
}

fn 材質を作る() -> マテリアルデータ {
    マテリアルデータ::金属粗さPBR(金属粗さPBRデータ {
        ベースカラー: None,
        金属粗さ: None,
        法線マップ: None,
        ベースカラー係数: [0.13, 0.19, 0.09, 1.0],
        金属度係数: 0.0,
        粗さ係数: 0.9,
    })
}
