//! 粗いセルの一辺を等分する細分点の表。細分点の位置比を持ち、走査へ配る。

use super::error::遠景コンパイルエラー;
use super::grid_measure::{格子の数を実数へ写す, 細分数, 細分数を実数へ写す};

/// セルの一辺を等分した点1つ。番号はセルの北西の隅から数えた並び、位置比はセルの一辺を1とした無次元の位置である。
#[derive(Debug, Clone, Copy)]
pub(super) struct 細分点 {
    pub(super) 番号: u32,
    pub(super) 位置比: f32,
}

/// セルの一辺に並ぶ細分点の表。
///
/// 表を持つのは、位置比が細分数だけで決まりセルごとに変わらないためである。標本ごとに位置比を割り算で作ると、
/// 数千万の標本を走査する間ずっと同じ17個の値を作り直すことになる。
pub(super) struct 細分点の表 {
    一覧: Vec<細分点>,
}

impl 細分点の表 {
    pub(super) fn 生成する() -> Result<Self, 遠景コンパイルエラー> {
        let 分母 = 細分数を実数へ写す()?;
        let mut 一覧 = Vec::with_capacity(usize::try_from(細分数).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)? + 1);
        for 番号 in 0..=細分数 {
            一覧.push(細分点 {
                番号,
                位置比: 格子の数を実数へ写す(番号)? / 分母,
            });
        }
        Ok(Self { 一覧 })
    }

    pub(super) fn 一覧(&self) -> &[細分点] {
        &self.一覧
    }
}
