//! 沈めた粗い格子を通常メッシュへ変換する。

use blitz_engine::{メッシュデータ, メッシュ頂点属性};
use blitz_math::{大域メートル, 大域ワールド位置};

use super::error::遠景コンパイルエラー;
use super::grid::{粗い刻みメートル, 遠景格子};

pub(super) fn 沈めたメッシュを作る(格子: &遠景格子, 沈み: &[f32]) -> Result<メッシュデータ, 遠景コンパイルエラー> {
    let mut 頂点一覧 = Vec::new();
    for 南 in 0..=格子.南セル数 {
        for 東 in 0..=格子.東セル数 {
            頂点一覧.push(頂点を作る(格子, 沈み, 東, 南)?);
        }
    }
    let mut インデックス一覧 = Vec::new();
    for 南 in 0..格子.南セル数 {
        for 東 in 0..格子.東セル数 {
            let 左上 = u32::try_from(格子.頂点添字(東, 南)?).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?;
            let 右上 = u32::try_from(格子.頂点添字(東 + 1, 南)?).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?;
            let 左下 = u32::try_from(格子.頂点添字(東, 南 + 1)?).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?;
            let 右下 = u32::try_from(格子.頂点添字(東 + 1, 南 + 1)?).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?;
            インデックス一覧.extend_from_slice(&[左上, 左下, 右下, 左上, 右下, 右上]);
        }
    }
    Ok(メッシュデータ::単一プリミティブで生成する(
        頂点一覧,
        インデックス一覧,
        None,
    ))
}

fn 頂点を作る(格子: &遠景格子, 沈み: &[f32], 東: u32, 南: u32) -> Result<メッシュ頂点属性, 遠景コンパイルエラー> {
    let 諸元 = 格子.高さ場.諸元();
    let 原点 = 大域ワールド位置::生成する(諸元.格子原点の東成分(), 大域メートル::生成する(0.0), 諸元.格子原点の南成分())
        .局所ワールド位置へ狭める(大域ワールド位置::原点())?;
    let 東実数 = f32::from(u16::try_from(東).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?);
    let 南実数 = f32::from(u16::try_from(南).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?);
    let 添字 = 格子.頂点添字(東, 南)?;
    let 高さ = 格子.粗い高さ(東, 南)? - 沈み[添字];
    let 傾き東 = 傾き(格子, 東, 南, true)?;
    let 傾き南 = 傾き(格子, 東, 南, false)?;
    let 法線 = 正規化する([-傾き東, 1.0, -傾き南]);
    let 接線方向 = 正規化する([1.0, 傾き東, 0.0]);
    Ok(メッシュ頂点属性 {
        位置: [原点.x().値() + 東実数 * 粗い刻みメートル, 高さ, 原点.z().値() + 南実数 * 粗い刻みメートル],
        法線,
        接線: [接線方向[0], 接線方向[1], 接線方向[2], 1.0],
        uv: [東実数 / 4.0, 1.0 - 南実数 / 4.0],
    })
}

fn 傾き(格子: &遠景格子, 東: u32, 南: u32, 東方向: bool) -> Result<f32, 遠景コンパイルエラー> {
    let (現在, 上限) = if 東方向 {
        (東, 格子.東セル数)
    } else {
        (南, 格子.南セル数)
    };
    let 前 = if 現在 == 0 { 0 } else { 現在 - 1 };
    let 後 = if 現在 == 上限 { 上限 } else { 現在 + 1 };
    let 前高さ = if 東方向 {
        格子.粗い高さ(前, 南)?
    } else {
        格子.粗い高さ(東, 前)?
    };
    let 後高さ = if 東方向 {
        格子.粗い高さ(後, 南)?
    } else {
        格子.粗い高さ(東, 後)?
    };
    let 幅 = f32::from(u16::try_from(後 - 前).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?) * 粗い刻みメートル;
    Ok((後高さ - 前高さ) / 幅)
}

fn 正規化する(値: [f32; 3]) -> [f32; 3] {
    let 長さ = (値[0] * 値[0] + 値[1] * 値[1] + 値[2] * 値[2]).sqrt();
    [値[0] / 長さ, 値[1] / 長さ, 値[2] / 長さ]
}
