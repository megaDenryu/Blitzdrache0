//! 沈めた粗い格子を通常メッシュへ変換する。

use blitz_engine::メッシュデータ;
use blitz_math::{ワールド, 位置, 大域メートル, 大域ワールド位置};

use super::error::遠景コンパイルエラー;
use super::grid::遠景格子;
use super::sink::頂点ごとの沈み;
use super::vertex::頂点の素材;

pub(super) fn 沈めたメッシュを作る(
    格子: &遠景格子,
    沈み: &頂点ごとの沈み,
) -> Result<メッシュデータ, 遠景コンパイルエラー> {
    let 格子原点 = 格子原点の局所位置を求める(格子)?;
    let mut 頂点一覧 = Vec::new();
    for 南 in 0..=格子.南セル数 {
        for 東 in 0..=格子.東セル数 {
            頂点一覧.push(頂点の素材::求める(格子, 沈み, 格子原点, 東, 南)?.頂点属性へ書き出す());
        }
    }
    Ok(メッシュデータ::単一プリミティブで生成する(
        頂点一覧,
        インデックス一覧を作る(格子)?,
        None,
    ))
}

/// 高さ場の諸元が持つ大域の格子原点を、世界原点からの局所位置へ狭める。頂点ごとに諸元を読み直さないよう1度だけ求める。
fn 格子原点の局所位置を求める(格子: &遠景格子) -> Result<位置<ワールド>, 遠景コンパイルエラー> {
    let 諸元 = 格子.諸元();
    let 大域の格子原点 = 大域ワールド位置::生成する(諸元.格子原点の東成分(), 大域メートル::生成する(0.0), 諸元.格子原点の南成分());
    Ok(大域の格子原点.局所ワールド位置へ狭める(大域ワールド位置::原点())?)
}

fn インデックス一覧を作る(格子: &遠景格子) -> Result<Vec<u32>, 遠景コンパイルエラー> {
    let mut インデックス一覧 = Vec::new();
    for 南 in 0..格子.南セル数 {
        for 東 in 0..格子.東セル数 {
            let 北西 = 頂点添字をインデックスへ写す(格子, 東, 南)?;
            let 北東 = 頂点添字をインデックスへ写す(格子, 東 + 1, 南)?;
            let 南西 = 頂点添字をインデックスへ写す(格子, 東, 南 + 1)?;
            let 南東 = 頂点添字をインデックスへ写す(格子, 東 + 1, 南 + 1)?;
            インデックス一覧.extend_from_slice(&[北西, 南西, 南東, 北西, 南東, 北東]);
        }
    }
    Ok(インデックス一覧)
}

fn 頂点添字をインデックスへ写す(格子: &遠景格子, 東: u32, 南: u32) -> Result<u32, 遠景コンパイルエラー> {
    u32::try_from(格子.頂点添字(東, 南)?).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)
}
