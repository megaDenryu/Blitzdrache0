//! 粗い格子の形を決める数と、格子の数え上げの値を計算に使える形へ読み替える口。
//!
//! 25メートルという刻みと16という細分数は、格子・走査・メッシュ組み立ての3者がどれも読む。読み替えを1箇所へ置くのは、
//! 同じ変換を3者が別々に書くと、数え切れないほど大きい値が来たときの扱いが場所ごとに散るためである。

use blitz_math::メートル;

use super::error::遠景コンパイルエラー;

/// 粗いセルの一辺を何等分して詳細面と見比べるか。高さ場の格子間隔にこの数を掛けたものが粗い格子の刻み幅になる。
pub(super) const 細分数: u32 = 16;

/// 粗い格子の1辺の長さ。
pub(super) fn 粗い格子の刻み幅() -> メートル {
    メートル::生成する(25.0)
}

/// 細分数を実数として読み直した値。細分点の位置比の分母がこれである。
pub(super) fn 細分数を実数へ写す() -> Result<f32, 遠景コンパイルエラー> {
    格子の数を実数へ写す(細分数)
}

/// セルの一辺に並ぶ細分点の数。両端を数えるため細分数より1つ多い。
pub(super) fn セルの一辺の細分点の数() -> Result<usize, 遠景コンパイルエラー> {
    let 刻みの数 = usize::try_from(細分数).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?;
    Ok(刻みの数 + 1)
}

/// 格子の点数・添字のような数え上げの値を単精度実数へ写す。単精度が1刻みで数え切れる範囲を超えたら失敗にする。
pub(super) fn 格子の数を実数へ写す(値: u32) -> Result<f32, 遠景コンパイルエラー> {
    let 収まる値 = u16::try_from(値).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?;
    Ok(f32::from(収まる値))
}
