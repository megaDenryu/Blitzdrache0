//! 粗いセルの中の細分点を走査して量を測る器。格子と細分点の表を保持し、標本ごとの下ごしらえを1度だけにする。
//!
//! 走査は2つある。沈める前の粗い面が詳細面より上へ出た量と、沈めた後の面と詳細面の隙間である。
//!
//! 注意: この2つを標本1回の走査へ畳むことはできない。頂点の沈みはその頂点に触れる最大4つのセルの偏差の最大で
//! 決まるため、あるセルの隙間を測るには周りのセルの偏差が先に出そろっている必要がある。畳めるのは走査の下ごしらえ
//! (細分点の位置比と四隅の読み出し)までであり、それをこの型が受け持つ。

use blitz_math::メートル;

use super::cell_corner::セルの四隅;
use super::deviation::セルごとの最大正偏差;
use super::error::遠景コンパイルエラー;
use super::gap::隙間の集計;
use super::grid::遠景格子;
use super::grid_measure::細分数;
use super::sink::頂点ごとの沈み;
use super::subdivision_point::細分点の表;

pub(super) struct 細分点の走査<'格子> {
    格子: &'格子 遠景格子,
    細分点の表: 細分点の表,
}

impl<'格子> 細分点の走査<'格子> {
    pub(super) fn 生成する(格子: &'格子 遠景格子) -> Result<Self, 遠景コンパイルエラー> {
        Ok(Self {
            格子,
            細分点の表: 細分点の表::生成する()?,
        })
    }

    pub(super) fn セルごとの最大正偏差を求める(&self) -> Result<セルごとの最大正偏差, 遠景コンパイルエラー> {
        let mut 一覧 = Vec::new();
        for 南 in 0..self.格子.南セル数 {
            for 東 in 0..self.格子.東セル数 {
                let 四隅 = セルの四隅::粗い格子から読む(self.格子, 東, 南)?;
                一覧.push(self.セルの最大正偏差を測る(&四隅, 東, 南)?);
            }
        }
        Ok(セルごとの最大正偏差::走査の並びから生成する(一覧))
    }

    pub(super) fn 沈めた面と詳細面の隙間を調べる(
        &self,
        沈み: &頂点ごとの沈み,
    ) -> Result<隙間の集計, 遠景コンパイルエラー> {
        let mut 集計 = 隙間の集計::標本を数える前の集計();
        for 南 in 0..self.格子.南セル数 {
            for 東 in 0..self.格子.東セル数 {
                let 四隅 = セルの四隅::沈めた粗い格子から読む(self.格子, 沈み, 東, 南)?;
                集計.別の集計を取り込む(&self.セルの隙間を測る(&四隅, 東, 南)?);
            }
        }
        Ok(集計)
    }

    fn セルの最大正偏差を測る(
        &self, 四隅: &セルの四隅, 東: u32, 南: u32
    ) -> Result<メートル, 遠景コンパイルエラー> {
        let mut 最大 = メートル::生成する(0.0);
        for 南点 in self.細分点の表.一覧() {
            let 詳細の行 = self.格子.セルの細かい高さの行(東, 南 * 細分数 + 南点.番号)?;
            for (東点, 詳細) in self.細分点の表.一覧().iter().zip(詳細の行) {
                let 粗い = 四隅.面の高さ(東点.位置比, 南点.位置比);
                let 偏差 = 粗い - *詳細;
                if 偏差 > 最大 {
                    最大 = 偏差;
                }
            }
        }
        Ok(最大)
    }

    fn セルの隙間を測る(&self, 四隅: &セルの四隅, 東: u32, 南: u32) -> Result<隙間の集計, 遠景コンパイルエラー> {
        let mut 集計 = 隙間の集計::標本を数える前の集計();
        for 南点 in self.細分点の表.一覧() {
            let 詳細の行 = self.格子.セルの細かい高さの行(東, 南 * 細分数 + 南点.番号)?;
            for (東点, 詳細) in self.細分点の表.一覧().iter().zip(詳細の行) {
                let 遠景 = 四隅.面の高さ(東点.位置比, 南点.位置比);
                集計.隙間を1つ数える(*詳細 - 遠景);
            }
        }
        Ok(集計)
    }
}
