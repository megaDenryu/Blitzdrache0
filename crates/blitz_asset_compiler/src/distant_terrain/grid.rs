//! 高さ場を25メートル刻みの粗い格子として参照する器。

use blitz_engine::height_field::{高さ場, 高さ場諸元};
use blitz_math::メートル;

use super::error::遠景コンパイルエラー;
use super::grid_measure::{セルの一辺の細分点の数, 粗い格子の刻み幅, 細分数, 細分数を実数へ写す};

/// 刻みの一致を確かめるときに見逃す差。格子間隔を単精度で持ったことによる丸めだけを吸収する幅である。
const 刻みの許容差: f32 = 1.0e-6;

pub(super) struct 遠景格子 {
    高さ場: 高さ場,
    pub(super) 東セル数: u32,
    pub(super) 南セル数: u32,
}

impl 遠景格子 {
    pub(super) fn 高さ場から作る(高さ場: 高さ場) -> Result<Self, 遠景コンパイルエラー> {
        let 諸元 = 高さ場.諸元();
        let 東区間 = 諸元.東方向の格子点数() - 1;
        let 南区間 = 諸元.南方向の格子点数() - 1;
        let 刻み差 = 諸元.格子間隔() * 細分数を実数へ写す()? - 粗い格子の刻み幅();
        let 許容の上 = メートル::生成する(刻みの許容差);
        let 許容の下 = メートル::生成する(-刻みの許容差);
        if !東区間.is_multiple_of(細分数) || !南区間.is_multiple_of(細分数) || 刻み差 > 許容の上 || 刻み差 < 許容の下 {
            return Err(遠景コンパイルエラー::格子寸法不一致);
        }
        Ok(Self {
            高さ場,
            東セル数: 東区間 / 細分数,
            南セル数: 南区間 / 細分数,
        })
    }

    pub(super) fn 諸元(&self) -> 高さ場諸元 {
        self.高さ場.諸元()
    }

    /// セル1つ分の細分点が東方向に並ぶ行。長さは細分数に1を足した数である。
    ///
    /// 行ごとにまとめて取り出すのは、標本1つずつに添字を組み立て直すのをやめるためである。走査は数千万の標本に及び、
    /// 標本ごとの添字の掛け算と範囲検査がそのまま数千万回になる。
    pub(super) fn セルの細かい高さの行(&self, 東セル: u32, 細南: u32) -> Result<&[メートル], 遠景コンパイルエラー> {
        let 東の先頭 = 東セル.checked_mul(細分数).ok_or(遠景コンパイルエラー::格子添字表現不能)?;
        let 先頭 = 細南
            .checked_mul(self.諸元().東方向の格子点数())
            .and_then(|行の先頭| 行の先頭.checked_add(東の先頭))
            .ok_or(遠景コンパイルエラー::格子添字表現不能)?;
        let 先頭 = usize::try_from(先頭).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?;
        let 終端 = 先頭
            .checked_add(セルの一辺の細分点の数()?)
            .ok_or(遠景コンパイルエラー::格子添字表現不能)?;
        self.高さ場
            .高さ一覧()
            .get(先頭..終端)
            .ok_or(遠景コンパイルエラー::細分点の行を取り出せない)
    }

    /// 粗い格子の格子点の高さ。粗い格子の頂点は、細かい格子を細分数ごとに間引いた点そのものである。
    pub(super) fn 粗い高さ(&self, 東: u32, 南: u32) -> Result<メートル, 遠景コンパイルエラー> {
        let 細東 = 東.checked_mul(細分数).ok_or(遠景コンパイルエラー::格子添字表現不能)?;
        let 細南 = 南.checked_mul(細分数).ok_or(遠景コンパイルエラー::格子添字表現不能)?;
        Ok(self.高さ場.格子点の高さ(細東, 細南)?)
    }

    pub(super) fn 頂点添字(&self, 東: u32, 南: u32) -> Result<usize, 遠景コンパイルエラー> {
        let 幅 = self.東セル数 + 1;
        let 添字 = 南
            .checked_mul(幅)
            .and_then(|先頭| 先頭.checked_add(東))
            .ok_or(遠景コンパイルエラー::格子添字表現不能)?;
        usize::try_from(添字).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)
    }

    pub(super) fn 頂点数(&self) -> Result<usize, 遠景コンパイルエラー> {
        Ok(self.頂点添字(self.東セル数, self.南セル数)? + 1)
    }
}
