//! 遠景を沈める量の分布と、詳細面との最小隙間の報告。

use blitz_math::{パーセンタイル順位, メートル, 昇順に並べた標本列, 順位から添字を選ぶ規則};

use super::deviation::セルごとの最大正偏差;
use super::error::遠景コンパイルエラー;
use super::gap::隙間の集計;

/// この統計が添字を選ぶ規則。寄せる前からこの規則であり、報告の値を動かさないために変えない。
const 添字を選ぶ規則: 順位から添字を選ぶ規則 = 順位から添字を選ぶ規則::最後の添字を基準にした切り捨て;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 遠景の沈み統計 {
    pub セル数: usize,
    pub 最大偏差: メートル,
    pub 中央値: メートル,
    pub 九十五パーセンタイル値: メートル,
    pub 九十九パーセンタイル値: メートル,
    pub 最小隙間: メートル,
    pub 正でない隙間数: usize,
    pub 安全幅: メートル,
}

impl 遠景の沈み統計 {
    pub(super) fn 求める(偏差: &セルごとの最大正偏差, 隙間: &隙間の集計, 安全幅: メートル) -> Result<Self, 遠景コンパイルエラー> {
        let mut 写し = 偏差.写し();
        let 標本列 = 昇順に並べた標本列::並べ替えて生成する(&mut 写し);
        let 最大偏差 = 標本列.最大().unwrap_or_else(|| メートル::生成する(0.0));
        隙間.正でない隙間があれば失敗にする()?;
        Ok(Self {
            セル数: 標本列.件数(),
            最大偏差,
            中央値: 百分位(&標本列, 50.0),
            九十五パーセンタイル値: 百分位(&標本列, 95.0),
            九十九パーセンタイル値: 百分位(&標本列, 99.0),
            最小隙間: 隙間.最小隙間(),
            正でない隙間数: 隙間.正でない隙間数(),
            安全幅,
        })
    }

    /// 検収が読む報告の1行。
    ///
    /// 注意: 文字列は数値の単位型を持てないため、統計の値をここで生の実数へ戻す。
    /// 文字列と桁数は検収との契約であり、勝手に変えると読み取りが黙って外れる。
    /// 参照: `xtask/src/game_fox_tour/map_generation_check/tally_line.rs`
    pub fn 報告の行を作る(self) -> String {
        format!(
            "遠景沈み 安全幅={:.3}m セル数={} 最大偏差={:.3}m 中央値={:.3}m p95={:.3}m p99={:.3}m 最小隙間={:.6}m 非正隙間={}",
            self.安全幅.値(),
            self.セル数,
            self.最大偏差.値(),
            self.中央値.値(),
            self.九十五パーセンタイル値.値(),
            self.九十九パーセンタイル値.値(),
            self.最小隙間.値(),
            self.正でない隙間数
        )
    }
}

fn 百分位(標本列: &昇順に並べた標本列<'_, メートル>, 順位: f32) -> メートル {
    標本列.パーセンタイル値を求める(パーセンタイル順位::百分率から生成する(順位), 添字を選ぶ規則).unwrap_or_else(|| メートル::生成する(0.0))
}
