//! 遠景を沈める量の分布と、詳細面との最小隙間を集計する。

use super::error::遠景コンパイルエラー;
use super::grid::{三角形の高さ, 細分数, 遠景格子};

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 遠景の沈み統計 {
    pub セル数: usize,
    pub 最大偏差: f32,
    pub 中央値: f32,
    pub p95: f32,
    pub p99: f32,
    pub 最小隙間: f32,
    pub 正でない隙間数: usize,
    pub 安全幅メートル: f32,
}

impl 遠景の沈み統計 {
    pub fn 報告の行を作る(self) -> String {
        format!(
            "遠景沈み 安全幅={:.3}m セル数={} 最大偏差={:.3}m 中央値={:.3}m p95={:.3}m p99={:.3}m 最小隙間={:.6}m 非正隙間={}",
            self.安全幅メートル, self.セル数, self.最大偏差, self.中央値, self.p95, self.p99, self.最小隙間, self.正でない隙間数
        )
    }
}

pub(super) fn 統計を求める(
    格子: &遠景格子,
    偏差: &[f32],
    沈み: &[f32],
    安全幅: f32,
) -> Result<遠景の沈み統計, 遠景コンパイルエラー> {
    let mut 並び = 偏差.to_vec();
    並び.sort_by(f32::total_cmp);
    let 最大偏差 = match 並び.last() {
        Some(値) => *値,
        None => 0.0,
    };
    let (最小隙間, 正でない隙間数) = 隙間を調べる(格子, 沈み)?;
    if 正でない隙間数 != 0 {
        return Err(遠景コンパイルエラー::正でない隙間(正でない隙間数));
    }
    Ok(遠景の沈み統計 {
        セル数: 並び.len(),
        最大偏差,
        中央値: 百分位(&並び, 50),
        p95: 百分位(&並び, 95),
        p99: 百分位(&並び, 99),
        最小隙間,
        正でない隙間数,
        安全幅メートル: 安全幅,
    })
}

fn 百分位(並び: &[f32], 百分率: usize) -> f32 {
    if 並び.is_empty() {
        return 0.0;
    }
    let 添字 = (並び.len() - 1) * 百分率 / 100;
    並び[添字]
}

fn 隙間を調べる(格子: &遠景格子, 沈み: &[f32]) -> Result<(f32, usize), 遠景コンパイルエラー> {
    let 分母 = f32::from(u16::try_from(細分数).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?);
    let mut 最小 = f32::INFINITY;
    let mut 非正 = 0;
    for 南 in 0..格子.南セル数 {
        for 東 in 0..格子.東セル数 {
            let 隅 = 沈めた四隅(格子, 沈み, 東, 南)?;
            for 局所南 in 0..=細分数 {
                for 局所東 in 0..=細分数 {
                    let 東比 = f32::from(u16::try_from(局所東).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?) / 分母;
                    let 南比 = f32::from(u16::try_from(局所南).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?) / 分母;
                    let 遠景 = 三角形の高さ(隅[0], 隅[1], 隅[2], 隅[3], 東比, 南比);
                    let 詳細 = 格子.細かい高さ(東 * 細分数 + 局所東, 南 * 細分数 + 局所南)?;
                    let 隙間 = 詳細 - 遠景;
                    最小 = 最小.min(隙間);
                    if 隙間 <= 0.0 {
                        非正 += 1;
                    }
                }
            }
        }
    }
    Ok((最小, 非正))
}

fn 沈めた四隅(格子: &遠景格子, 沈み: &[f32], 東: u32, 南: u32) -> Result<[f32; 4], 遠景コンパイルエラー> {
    let mut 結果 = [0.0; 4];
    for (位置, (頂点東, 頂点南)) in [(東, 南), (東 + 1, 南), (東, 南 + 1), (東 + 1, 南 + 1)].into_iter().enumerate() {
        let 添字 = 格子.頂点添字(頂点東, 頂点南)?;
        結果[位置] = 格子.粗い高さ(頂点東, 頂点南)? - 沈み[添字];
    }
    Ok(結果)
}
