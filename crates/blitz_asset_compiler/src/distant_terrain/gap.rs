//! 沈めた遠景の面と詳細面の隙間の集計。最小の隙間と、隙間が正でなかった標本の数を持つ。
//!
//! 正でない隙間は遠景の面が詳細面を突き抜けたことを意味する。突き抜けたまま焼くと、近景と遠景が入れ替わる距離で
//! 地面が抜けて見える。数えた結果を失敗へ変える規則もこの型が持ち、集計と判定が離れないようにする。

use blitz_math::メートル;

use super::error::遠景コンパイルエラー;

pub(super) struct 隙間の集計 {
    最小隙間: メートル,
    正でない隙間数: usize,
}

impl 隙間の集計 {
    /// 標本を1つも数えていない集計。最小隙間の初期値は、最初の標本が必ず下回る無限とする。
    pub(super) fn 標本を数える前の集計() -> Self {
        Self {
            最小隙間: メートル::生成する(f32::INFINITY),
            正でない隙間数: 0,
        }
    }

    pub(super) fn 隙間を1つ数える(&mut self, 隙間: メートル) {
        if 隙間 < self.最小隙間 {
            self.最小隙間 = 隙間;
        }
        if 隙間 <= メートル::生成する(0.0) {
            self.正でない隙間数 += 1;
        }
    }

    /// セル1つ分の集計を取り込む。最小どうしの最小は全標本の最小に等しいため、セルごとに畳んでも結果は変わらない。
    pub(super) fn 別の集計を取り込む(&mut self, 他: &Self) {
        if 他.最小隙間 < self.最小隙間 {
            self.最小隙間 = 他.最小隙間;
        }
        self.正でない隙間数 += 他.正でない隙間数;
    }

    pub(super) fn 最小隙間(&self) -> メートル {
        self.最小隙間
    }

    pub(super) fn 正でない隙間数(&self) -> usize {
        self.正でない隙間数
    }

    pub(super) fn 正でない隙間があれば失敗にする(&self) -> Result<(), 遠景コンパイルエラー> {
        if self.正でない隙間数 == 0 {
            Ok(())
        } else {
            Err(遠景コンパイルエラー::正でない隙間(self.正でない隙間数))
        }
    }
}
