//! 粗いセルの四隅の高さと、その四隅が張る2枚の三角形の上の高さ。
//!
//! 四隅を1つの値としてまとめて持つのは、面の高さが四隅すべてを同時に見て初めて決まるためである。

use blitz_math::メートル;

use super::error::遠景コンパイルエラー;
use super::grid::遠景格子;
use super::sink::頂点ごとの沈み;

#[derive(Debug, Clone, Copy)]
pub(super) struct セルの四隅 {
    北西: メートル,
    北東: メートル,
    南西: メートル,
    南東: メートル,
}

impl セルの四隅 {
    /// 沈める前の粗い格子から四隅の高さを読む。
    pub(super) fn 粗い格子から読む(格子: &遠景格子, 東: u32, 南: u32) -> Result<Self, 遠景コンパイルエラー> {
        Ok(Self {
            北西: 格子.粗い高さ(東, 南)?,
            北東: 格子.粗い高さ(東 + 1, 南)?,
            南西: 格子.粗い高さ(東, 南 + 1)?,
            南東: 格子.粗い高さ(東 + 1, 南 + 1)?,
        })
    }

    /// 頂点ごとの沈みだけ下げた後の四隅の高さを読む。
    pub(super) fn 沈めた粗い格子から読む(
        格子: &遠景格子,
        沈み: &頂点ごとの沈み,
        東: u32,
        南: u32,
    ) -> Result<Self, 遠景コンパイルエラー> {
        Ok(Self {
            北西: 沈み.沈めた高さ(格子, 東, 南)?,
            北東: 沈み.沈めた高さ(格子, 東 + 1, 南)?,
            南西: 沈み.沈めた高さ(格子, 東, 南 + 1)?,
            南東: 沈み.沈めた高さ(格子, 東 + 1, 南 + 1)?,
        })
    }

    /// 四隅が張る2枚の三角形のうち、渡された位置比が乗る側の面の高さ。
    ///
    /// 注意: 加算の並びはメッシュの頂点高さと隙間の報告値をそのまま決める。並べ替えると報告値の下位ビットが動く。
    pub(super) fn 面の高さ(&self, 東比: f32, 南比: f32) -> メートル {
        if 東比 <= 南比 {
            self.北西 + (self.南西 - self.北西) * 南比 + (self.南東 - self.南西) * 東比
        } else {
            self.北西 + (self.北東 - self.北西) * 東比 + (self.南東 - self.北東) * 南比
        }
    }
}
