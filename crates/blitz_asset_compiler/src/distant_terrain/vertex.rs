//! 遠景メッシュの頂点1つ分の材料と、それを頂点属性の並びへ書き出す境界。

use blitz_engine::メッシュ頂点属性;
use blitz_math::{メートル, ワールド, 位置};

use super::error::遠景コンパイルエラー;
use super::grid::遠景格子;
use super::grid_measure::{格子の数を実数へ写す, 粗い格子の刻み幅};
use super::sink::頂点ごとの沈み;

/// 傾きを取るときに前後へ見る格子の添字。格子の端では片側だけを使い、格子の外を読まない。
struct 傾きを取る前後の添字 {
    前: u32,
    後: u32,
}

impl 傾きを取る前後の添字 {
    fn 求める(現在: u32, 上限: u32) -> Self {
        Self {
            前: if 現在 == 0 { 0 } else { 現在 - 1 },
            後: if 現在 == 上限 { 上限 } else { 現在 + 1 },
        }
    }

    fn 隔たりのセル数(&self) -> u32 {
        self.後 - self.前
    }
}

/// 頂点1つを決める量。位置と、法線・接線を導く2方向の高低差と水平距離を、単位を持ったまま並べる。
pub(super) struct 頂点の素材 {
    東座標: メートル,
    高さ: メートル,
    南座標: メートル,
    東方向の高低差: メートル,
    東方向の水平距離: メートル,
    南方向の高低差: メートル,
    南方向の水平距離: メートル,
    面上のuv: [f32; 2],
}

impl 頂点の素材 {
    pub(super) fn 求める(
        格子: &遠景格子,
        沈み: &頂点ごとの沈み,
        格子原点: 位置<ワールド>,
        東: u32,
        南: u32,
    ) -> Result<Self, 遠景コンパイルエラー> {
        let 東実数 = 格子の数を実数へ写す(東)?;
        let 南実数 = 格子の数を実数へ写す(南)?;
        let 東の前後 = 傾きを取る前後の添字::求める(東, 格子.東セル数);
        let 南の前後 = 傾きを取る前後の添字::求める(南, 格子.南セル数);
        Ok(Self {
            東座標: 格子原点.x() + 粗い格子の刻み幅() * 東実数,
            高さ: 沈み.沈めた高さ(格子, 東, 南)?,
            南座標: 格子原点.z() + 粗い格子の刻み幅() * 南実数,
            東方向の高低差: 格子.粗い高さ(東の前後.後, 南)? - 格子.粗い高さ(東の前後.前, 南)?,
            東方向の水平距離: 粗い格子の刻み幅() * 格子の数を実数へ写す(東の前後.隔たりのセル数())?,
            南方向の高低差: 格子.粗い高さ(東, 南の前後.後)? - 格子.粗い高さ(東, 南の前後.前)?,
            南方向の水平距離: 粗い格子の刻み幅() * 格子の数を実数へ写す(南の前後.隔たりのセル数())?,
            面上のuv: [東実数 / 4.0, 1.0 - 南実数 / 4.0],
        })
    }

    /// 注意: 遠景の高さと座標が単位型を離れる唯一の場所である。頂点属性はGPUへ送る数値の並びであり単位型を持てないため、
    /// ここでだけ値を取り出す。取り出した実数をこの関数の外へ返さない。傾きは長さを長さで割った無次元量であり、
    /// 単位型では表せないためここで求める。
    pub(super) fn 頂点属性へ書き出す(&self) -> メッシュ頂点属性 {
        let 東方向の傾き = self.東方向の高低差.値() / self.東方向の水平距離.値();
        let 南方向の傾き = self.南方向の高低差.値() / self.南方向の水平距離.値();
        let 接線方向 = 正規化する([1.0, 東方向の傾き, 0.0]);
        メッシュ頂点属性 {
            位置: [self.東座標.値(), self.高さ.値(), self.南座標.値()],
            法線: 正規化する([-東方向の傾き, 1.0, -南方向の傾き]),
            接線: [接線方向[0], 接線方向[1], 接線方向[2], 1.0],
            uv: self.面上のuv,
        }
    }
}

fn 正規化する(値: [f32; 3]) -> [f32; 3] {
    let 長さ = (値[0] * 値[0] + 値[1] * 値[1] + 値[2] * 値[2]).sqrt();
    [値[0] / 長さ, 値[1] / 長さ, 値[2] / 長さ]
}
