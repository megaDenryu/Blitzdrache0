//! 遠景メッシュの入力・算術・格納の失敗。

#[derive(Debug, thiserror::Error)]
pub enum 遠景コンパイルエラー {
    #[error("高さ格子の読み出しに失敗した: {0}")]
    高さ格子(#[from] crate::height_grid::高さ格子エラー),
    #[error("高さ場の組み立てに失敗した: {0}")]
    高さ場(#[from] crate::height_field::高さ場コンパイルエラー),
    #[error("高さ場の参照に失敗した: {0}")]
    高さ場参照(#[from] blitz_engine::height_field::高さ場エラー),
    #[error("遠景の格子寸法が25メートル刻みと一致しない")]
    格子寸法不一致,
    #[error("遠景の安全幅が正の有限値でない: {0}")]
    安全幅不正(f32),
    #[error("遠景の格子添字を表現できない")]
    格子添字表現不能,
    #[error("大域位置を単精度へ狭められない: {0}")]
    大域位置(#[from] blitz_math::座標変換エラー),
    #[error("沈めた遠景と詳細面の隙間が正でない点が{0}件ある")]
    正でない隙間(usize),
    #[error("遠景シーンの格納に失敗した: {0}")]
    シーン(#[from] crate::error::アセットコンパイルエラー),
}
