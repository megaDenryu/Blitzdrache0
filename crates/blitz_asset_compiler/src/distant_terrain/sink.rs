//! 粗い格子の頂点をどれだけ下へずらすかの一覧。値は、その頂点に触れるセルの最大正偏差に安全幅を足した量である。
//!
//! 添字は遠景格子の頂点添字である。沈めた高さを求める規則をこの型の中へ置くのは、
//! 「粗い高さから自分の沈みを引く」という同じ式をメッシュの組み立てと隙間の走査が二重に持たないためである。

use blitz_math::メートル;

use super::deviation::セルごとの最大正偏差;
use super::error::遠景コンパイルエラー;
use super::grid::遠景格子;

pub(super) struct 頂点ごとの沈み {
    一覧: Vec<メートル>,
}

impl 頂点ごとの沈み {
    pub(super) fn 求める(
        格子: &遠景格子, 偏差: &セルごとの最大正偏差, 安全幅: メートル
    ) -> Result<Self, 遠景コンパイルエラー> {
        安全幅が正の有限値か確かめる(安全幅)?;
        let mut 一覧 = vec![メートル::生成する(0.0); 格子.頂点数()?];
        let mut セル添字 = 0_usize;
        for 南 in 0..格子.南セル数 {
            for 東 in 0..格子.東セル数 {
                let 値 = 偏差.セルの偏差(セル添字)?;
                for (頂点東, 頂点南) in [(東, 南), (東 + 1, 南), (東, 南 + 1), (東 + 1, 南 + 1)] {
                    let 添字 = 格子.頂点添字(頂点東, 頂点南)?;
                    let 場所 = 一覧.get_mut(添字).ok_or(遠景コンパイルエラー::格子添字表現不能)?;
                    if 値 > *場所 {
                        *場所 = 値;
                    }
                }
                セル添字 += 1;
            }
        }
        for 値 in &mut 一覧 {
            *値 = *値 + 安全幅;
        }
        Ok(Self { 一覧 })
    }

    pub(super) fn 頂点の沈み(&self, 添字: usize) -> Result<メートル, 遠景コンパイルエラー> {
        self.一覧.get(添字).copied().ok_or(遠景コンパイルエラー::格子添字表現不能)
    }

    /// 粗い格子の頂点を、その頂点の沈みだけ下げた高さ。
    pub(super) fn 沈めた高さ(&self, 格子: &遠景格子, 東: u32, 南: u32) -> Result<メートル, 遠景コンパイルエラー> {
        let 沈み = self.頂点の沈み(格子.頂点添字(東, 南)?)?;
        Ok(格子.粗い高さ(東, 南)? - 沈み)
    }
}

/// 非数と無限を大小の比較だけで弾く。0より大きく無限より小さい値だけが両方の比較を通る。
fn 安全幅が正の有限値か確かめる(安全幅: メートル) -> Result<(), 遠景コンパイルエラー> {
    let 零 = メートル::生成する(0.0);
    let 無限 = メートル::生成する(f32::INFINITY);
    if 安全幅 > 零 && 安全幅 < 無限 {
        Ok(())
    } else {
        Err(遠景コンパイルエラー::安全幅不正(安全幅.値()))
    }
}
