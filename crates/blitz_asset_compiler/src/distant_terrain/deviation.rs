//! セルごとの最大正偏差の一覧。正偏差とは、粗い面が詳細面より上へ出た量のことである。
//!
//! 添字はセルの走査順(南が外側・東が内側)である。頂点ごとの沈みと百分位の両方がこの並びを読むため、
//! 並びの意味をこの型の中へ閉じ、走査した側と読む側が並べ方を二重に覚えないようにする。

use blitz_math::メートル;

use super::error::遠景コンパイルエラー;

pub(super) struct セルごとの最大正偏差 {
    一覧: Vec<メートル>,
}

impl セルごとの最大正偏差 {
    pub(super) fn 走査の並びから生成する(一覧: Vec<メートル>) -> Self {
        Self { 一覧 }
    }

    pub(super) fn セルの偏差(&self, 添字: usize) -> Result<メートル, 遠景コンパイルエラー> {
        self.一覧.get(添字).copied().ok_or(遠景コンパイルエラー::格子添字表現不能)
    }

    /// 走査の並びのままの写し。パーセンタイル値を採る側が`昇順に並べた標本列`へ渡して並べ替える。
    ///
    /// 前提: 偏差は0メートルから始めて「より大きいときだけ入れ替える」形で求めるため、非数は現れない。
    /// 並べ替えが使う全順序は非数を最も大きい側へ置くが、非数が現れない以上その枝には入らない。
    pub(super) fn 写し(&self) -> Vec<メートル> {
        self.一覧.clone()
    }
}
