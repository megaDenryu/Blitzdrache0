//! 詳細面に対する粗い三角形の正偏差と、粗い頂点ごとの沈みを求める。

use super::error::遠景コンパイルエラー;
use super::grid::{三角形の高さ, 細分数, 遠景格子};

pub(super) fn セルごとの最大正偏差を求める(格子: &遠景格子) -> Result<Vec<f32>, 遠景コンパイルエラー> {
    let mut 結果 = Vec::new();
    for 南 in 0..格子.南セル数 {
        for 東 in 0..格子.東セル数 {
            結果.push(セルの最大正偏差(格子, 東, 南)?);
        }
    }
    Ok(結果)
}

fn セルの最大正偏差(格子: &遠景格子, 東: u32, 南: u32) -> Result<f32, 遠景コンパイルエラー> {
    let 左上 = 格子.粗い高さ(東, 南)?;
    let 右上 = 格子.粗い高さ(東 + 1, 南)?;
    let 左下 = 格子.粗い高さ(東, 南 + 1)?;
    let 右下 = 格子.粗い高さ(東 + 1, 南 + 1)?;
    let 分母 = f32::from(u16::try_from(細分数).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?);
    let mut 最大 = 0.0_f32;
    for 局所南 in 0..=細分数 {
        for 局所東 in 0..=細分数 {
            let 東比 = f32::from(u16::try_from(局所東).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?) / 分母;
            let 南比 = f32::from(u16::try_from(局所南).map_err(|_| 遠景コンパイルエラー::格子添字表現不能)?) / 分母;
            let 粗い = 三角形の高さ(左上, 右上, 左下, 右下, 東比, 南比);
            let 詳細 = 格子.細かい高さ(東 * 細分数 + 局所東, 南 * 細分数 + 局所南)?;
            最大 = 最大.max(粗い - 詳細);
        }
    }
    Ok(最大)
}

pub(super) fn 頂点ごとの沈みを求める(
    格子: &遠景格子, 偏差: &[f32], 安全幅: f32
) -> Result<Vec<f32>, 遠景コンパイルエラー> {
    if !安全幅.is_finite() || 安全幅 <= 0.0 {
        return Err(遠景コンパイルエラー::安全幅不正(安全幅));
    }
    let 頂点数 = 格子.頂点添字(格子.東セル数, 格子.南セル数)? + 1;
    let mut 沈み = vec![0.0_f32; 頂点数];
    let mut セル添字 = 0_usize;
    for 南 in 0..格子.南セル数 {
        for 東 in 0..格子.東セル数 {
            let 値 = *偏差.get(セル添字).ok_or(遠景コンパイルエラー::格子添字表現不能)?;
            for (頂点東, 頂点南) in [(東, 南), (東 + 1, 南), (東, 南 + 1), (東 + 1, 南 + 1)] {
                let 添字 = 格子.頂点添字(頂点東, 頂点南)?;
                沈み[添字] = 沈み[添字].max(値);
            }
            セル添字 += 1;
        }
    }
    for 値 in &mut 沈み {
        *値 += 安全幅;
    }
    Ok(沈み)
}
