//! glTFで書かれた1つのシーンを焼く工程。読み込みは`loader`の同名のメソッドへ委ね、ここが担うのは
//! 読み終えたシーンデータを実行時形式へ落とすことだけである。

use blitz_engine::{アセットID, チャンク座標};

use crate::scene_compiler::ソースアセットのコンパイル係;
use crate::uniform_scale::寸法を合わせる一様倍率;
use crate::アセットコンパイルエラー;

use super::コンパイル済みシーン;

impl ソースアセットのコンパイル係<'_> {
    pub fn ソースシーンをコンパイルする(
        &self,
        id: &アセットID,
        所有チャンク: チャンク座標,
    ) -> Result<コンパイル済みシーン, アセットコンパイルエラー> {
        self.寸法を合わせる倍率を与えてソースシーンをコンパイルする(id, 所有チャンク, 寸法を合わせる一様倍率::等倍())
    }

    /// 実寸のメートルで書かれていないソースを、倍率で実寸へ合わせながら焼く。標準サンプルのキツネのように、
    /// ソースの単位が世界の1メートルと違うアセットをこの入口が扱う。
    pub fn 寸法を合わせる倍率を与えてソースシーンをコンパイルする(
        &self,
        id: &アセットID,
        所有チャンク: チャンク座標,
        倍率: 寸法を合わせる一様倍率,
    ) -> Result<コンパイル済みシーン, アセットコンパイルエラー> {
        let シーン = self.寸法を合わせる倍率を与えてソースシーンを読み込む(id, 所有チャンク, 倍率)?;
        コンパイル済みシーン::シーンデータから焼く(シーン)
    }
}
