//! チャンク1つの高さ格子を、置き場と中身の2つの形で表す型。座標とファイル、座標と読み込んだ格子を、
//! 名前の無い組でなく名前のある型で運ぶ。
//!
//! 型にするのは、この2つ組が生成器・縁の一致の検査・高さ場の貼り合わせという3つの経路を横断するためである。
//! 組のまま運ぶと、どちらの成分が座標でどちらが中身かを呼び出し側が覚えることになり、既にある置き場の型も使われない。

use std::path::PathBuf;

use blitz_engine::チャンク座標;

use super::height_grid_file::高さ格子のファイル;
use crate::height_grid::{高さ格子, 高さ格子エラー};

/// 焼く前のチャンク1つ。どの座標のどのファイルかを持ち、読み込むと中身を持つ形へ変わる。
pub struct チャンクの高さ格子ソース {
    座標: チャンク座標,
    ファイル: 高さ格子のファイル,
}

impl チャンクの高さ格子ソース {
    pub fn 生成する(座標: チャンク座標, ファイル: 高さ格子のファイル) -> Self {
        Self { 座標, ファイル }
    }

    pub fn 座標(&self) -> チャンク座標 {
        self.座標
    }

    pub fn 読み込む(&self) -> Result<チャンクの高さ格子, 高さ格子エラー> {
        Ok(チャンクの高さ格子 {
            座標: self.座標,
            格子: self.ファイル.読み込む()?,
        })
    }

    /// カタログのソース依存一覧へ載せるためのパス。実行時形式の再生成の要否を見る側が読む。
    pub fn 依存一覧へ載せるパス(&self) -> PathBuf {
        self.ファイル.パスの写しを作る()
    }
}

/// 読み込んだチャンク1つ。縁の一致の検査と高さ場の貼り合わせがこの形で受け取る。
pub struct チャンクの高さ格子 {
    座標: チャンク座標,
    格子: 高さ格子,
}

impl チャンクの高さ格子 {
    pub fn 生成する(座標: チャンク座標, 格子: 高さ格子) -> Self {
        Self { 座標, 格子 }
    }

    pub fn 座標(&self) -> チャンク座標 {
        self.座標
    }

    pub fn 格子(&self) -> &高さ格子 {
        &self.格子
    }
}
