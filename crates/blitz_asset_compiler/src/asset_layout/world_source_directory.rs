//! 世界のソースディレクトリ: 1つの世界のソース一式が並ぶディレクトリを表す型。チャンク目録ソースのファイル名を持ち、
//! 直下のファイルのパスを組む。
//!
//! 世界のディレクトリ名の綴りをここへ集めるのは、ソースを書き出すバイナリと実行時形式へ焼くバイナリの両方が
//! 同じディレクトリを指す必要があるためである。2つの綴りを注意書きで同期させると、食い違ったときに
//! 「目録ソースが見つからない」という遠い場所の失敗になる。
//!
//! 置き場のパスは包んだ生成の出力ルートが1回だけ所有する。台帳の置き場として渡すときも借用で貸し、複製を作らない。

use std::path::{Path, PathBuf};

use crate::generation_ledger::生成の出力ルート;

/// どの世界のソースディレクトリにも同じ名前で置く、チャンク目録ソースのファイル名。
pub(super) const チャンク目録ソースのファイル名: &str = "chunk_directory.txt";

/// クソゲー1本目「キツネの場所巡り」が遊ばれる世界のディレクトリ名。乱数の種から書き出す側と、実行時形式へ焼く側が
/// この1つを読む。
pub const 場所巡りの世界のディレクトリ名: &str = "fox_tour_world";

#[repr(transparent)]
pub struct 世界のソースディレクトリ(生成の出力ルート);

impl 世界のソースディレクトリ {
    pub(super) fn パスから作る(ディレクトリ: PathBuf) -> Self {
        Self(生成の出力ルート::生成する(ディレクトリ))
    }

    /// ディレクトリを作ってから返す。書き出す側は最初にこれを通り、読む側は通らない。
    pub fn 作ってから開く(self) -> Result<Self, String> {
        self.0.ディレクトリを作る().map_err(|誤り| 誤り.to_string())?;
        Ok(self)
    }

    pub fn チャンク目録ソースのパス(&self) -> PathBuf {
        self.0.直下のファイルのパス(チャンク目録ソースのファイル名)
    }

    pub fn 直下のファイルのパス(&self, ファイル名: &str) -> PathBuf {
        self.0.直下のファイルのパス(ファイル名)
    }

    /// 目録の1行のように、置き場からの相対パスとして与えられたソースのパス。綴りへ写し替えずに組む。
    pub fn 直下の相対パスが指すファイル(&self, 相対パス: &Path) -> PathBuf {
        self.0.直下の相対パスが指すファイル(相対パス)
    }

    /// 生成台帳の置き場としてのこの置き場。台帳の読み書きは生成の出力ルートの側が担う。
    pub fn 台帳の置き場(&self) -> &生成の出力ルート {
        &self.0
    }

    pub fn 表示の綴り(&self) -> std::path::Display<'_> {
        self.0.表示の綴り()
    }
}
