//! アセットの置き場を組むときに破れうる前提の型付きエラー。世界のディレクトリ名が1つのディレクトリを指す1語であることが
//! ここで破れる。

use thiserror::Error;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum アセット配置エラー {
    #[error("世界のディレクトリ名が空である")]
    世界のディレクトリ名が空である,
    #[error("世界のディレクトリ名が区切りを含む: {0}")]
    世界のディレクトリ名が区切りを含む(&'static str),
    #[error("世界のディレクトリ名が上や今の場所を指す綴りである: {0}")]
    世界のディレクトリ名が場所を指す綴りである(&'static str),
}
