//! アセットの置き場を組み、その配下を読み書きするときに破れうる前提の型付きエラー。世界のディレクトリ名が1つの
//! ディレクトリを指す1語であることと、置き場の配下のファイルを実際に読み書きできることがここで破れる。
//!
//! 置き場の型が返す誤りをこの1つへ揃えるのは、同じ置き場の中で「名前の検証は型付き、書き出しは生の文」と
//! 分かれていると、呼び出し側が2つの受け方を書き分けることになるためである。
//!
//! 入出力の事由を`std::io::Error`のまま持たず綴りへ写すのは、生成台帳エラーと同じ様式に揃えるためである。

use std::path::PathBuf;

use thiserror::Error;

use crate::generation_ledger::生成台帳エラー;

#[derive(Debug, Error)]
pub enum アセット配置エラー {
    #[error("世界のディレクトリ名が空である")]
    世界のディレクトリ名が空である,
    #[error("世界のディレクトリ名が区切りを含む: {0}")]
    世界のディレクトリ名が区切りを含む(&'static str),
    #[error("世界のディレクトリ名が上や今の場所を指す綴りである: {0}")]
    世界のディレクトリ名が場所を指す綴りである(&'static str),
    #[error("世界のディレクトリ名が対象環境で使えない記号{記号}を含む: {名前}")]
    世界のディレクトリ名が使えない記号を含む { 名前: &'static str, 記号: char },
    #[error("世界のディレクトリ名が制御文字を含む: {0:?}")]
    世界のディレクトリ名が制御文字を含む(&'static str),
    #[error("世界のディレクトリ名が予約された装置の名前である: {0}")]
    世界のディレクトリ名が予約された装置の名前である(&'static str),
    #[error("世界のディレクトリ名が点か空白で終わる: {0:?}")]
    世界のディレクトリ名が点か空白で終わる(&'static str),
    #[error("置き場のディレクトリを用意できなかった: {0}")]
    置き場のディレクトリを用意できなかった(#[from] 生成台帳エラー),
    #[error("{}へ書き出せなかった: {事由}", パス.display())]
    ファイルへ書き出せなかった { パス: PathBuf, 事由: String },
    #[error("{}を読めなかった: {事由}", パス.display())]
    ファイルを読めなかった { パス: PathBuf, 事由: String },
    #[error("{}の乱数の種を32ビットの非負整数として読めない: {綴り:?}", パス.display())]
    乱数の種が不正 { パス: PathBuf, 綴り: String },
    #[error("チャンク世界のソースアセットが存在しない: {}", パス.display())]
    目録が指すチャンクのソースが無い { パス: PathBuf }, // 無いまま焼くと目録に載った座標だけが黙って欠ける
}
