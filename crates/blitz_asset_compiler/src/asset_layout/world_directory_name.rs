//! 世界のディレクトリ名: ソースルートの直下に置く1つの世界のディレクトリの名前を表す値オブジェクト。
//!
//! 裸の綴りで受け取らないのは、置き場を組む口へ任意の綴りが流れると、区切りを含む綴りでソースルートの外へ出られたり、
//! 空の綴りでルートそのものを世界のディレクトリとして扱えたりするためである。名前は1つのディレクトリを指す1語に限る。

use super::error::アセット配置エラー;

#[repr(transparent)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 世界のディレクトリ名(&'static str);

impl 世界のディレクトリ名 {
    /// 空でないこと、斜線と逆斜線のどちらの区切りも含まないこと、上や今の場所を指す綴りでないことを確かめる。
    /// 区切りを両方見るのは、綴りが動く先の環境によらず1つのディレクトリを指すことを保つためである。
    pub const fn 生成する(名前: &'static str) -> Result<Self, アセット配置エラー> {
        if 名前.is_empty() {
            return Err(アセット配置エラー::世界のディレクトリ名が空である);
        }
        if 区切りを含むか(名前) {
            return Err(アセット配置エラー::世界のディレクトリ名が区切りを含む(名前));
        }
        if 上や今の場所を指すか(名前) {
            return Err(アセット配置エラー::世界のディレクトリ名が場所を指す綴りである(名前));
        }
        Ok(Self(名前))
    }

    pub(super) fn 綴り(self) -> &'static str {
        self.0
    }

    /// 生成台帳の見出しへ焼き方の指定として載せるための綴り。パスを組む口ではない。
    pub fn 綴りを見せる(self) -> &'static str {
        self.0
    }
}

const fn 区切りを含むか(名前: &str) -> bool {
    let バイト列 = 名前.as_bytes();
    let mut 位置 = 0;
    while 位置 < バイト列.len() {
        let バイト = バイト列[位置];
        if バイト == b'/' || バイト == b'\\' {
            return true;
        }
        位置 += 1;
    }
    false
}

const fn 上や今の場所を指すか(名前: &str) -> bool {
    let バイト列 = 名前.as_bytes();
    if バイト列.len() == 1 && バイト列[0] == b'.' {
        return true;
    }
    バイト列.len() == 2 && バイト列[0] == b'.' && バイト列[1] == b'.'
}
