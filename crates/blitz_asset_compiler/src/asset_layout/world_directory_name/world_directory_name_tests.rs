//! 世界のディレクトリ名の反証。ソースルートの直下の1つの通常のディレクトリを指さない綴りを、構築の時点で拒むことを確かめる。
//!
//! 受理の側も一緒に確かめるのは、検証を強めた結果として現に使っている世界の名前まで拒んでしまう退行を止めるためである。

#![allow(clippy::unwrap_used)]

use super::super::error::アセット配置エラー;
use super::世界のディレクトリ名;

/// 現に使っている世界の名前と、同じ形の名前は通る。
#[test]
fn 通常のディレクトリ名を受理する() {
    for 名前 in ["fox_tour_world", "terrain_world", "texture_compression_world", "world-2", "世界"] {
        assert!(世界のディレクトリ名::生成する(名前).is_ok(), "受理されるべき名前が拒まれた: {名前}");
    }
}

/// 注意: ドライブ接頭辞つきの綴りは、Windowsの連結が基準の側を丸ごと置き換えるため、置き場がソースルートの外へ出る。
/// この1件がこの検証を強めた理由である。
#[test]
fn ドライブ接頭辞つきの綴りを拒む() {
    assert!(matches!(
        世界のディレクトリ名::生成する("C:escape"),
        Err(アセット配置エラー::世界のディレクトリ名が使えない記号を含む { 記号: ':', .. })
    ));
}

#[test]
fn 空と区切りと場所を指す綴りを拒む() {
    assert!(matches!(
        世界のディレクトリ名::生成する(""),
        Err(アセット配置エラー::世界のディレクトリ名が空である)
    ));
    for 名前 in ["a/b", r"a\b"] {
        assert!(matches!(
            世界のディレクトリ名::生成する(名前),
            Err(アセット配置エラー::世界のディレクトリ名が区切りを含む(_))
        ));
    }
    for 名前 in [".", ".."] {
        assert!(matches!(
            世界のディレクトリ名::生成する(名前),
            Err(アセット配置エラー::世界のディレクトリ名が場所を指す綴りである(_))
        ));
    }
}

#[test]
fn 対象環境で使えない記号と制御文字を拒む() {
    for 名前 in ["a*b", "a?b", "a<b", "a>b", "a|b"] {
        assert!(
            matches!(
                世界のディレクトリ名::生成する(名前),
                Err(アセット配置エラー::世界のディレクトリ名が使えない記号を含む { .. })
            ),
            "拒まれるべき名前が受理された: {名前}"
        );
    }
    assert!(matches!(
        世界のディレクトリ名::生成する("a\u{7}b"),
        Err(アセット配置エラー::世界のディレクトリ名が制御文字を含む(_))
    ));
}

/// 拡張子を付けても装置として解釈されるため、点より前だけを見て拒む。大文字と小文字は区別しない。
#[test]
fn 予約された装置の名前を拒む() {
    for 名前 in ["CON", "con", "NUL", "com1", "LPT9", "con.txt"] {
        assert!(
            matches!(
                世界のディレクトリ名::生成する(名前),
                Err(アセット配置エラー::世界のディレクトリ名が予約された装置の名前である(_))
            ),
            "拒まれるべき名前が受理された: {名前}"
        );
    }
}

/// Windowsが黙って落とすため、書いた名前と現物の名前が食い違う。
#[test]
fn 点か空白で終わる綴りを拒む() {
    for 名前 in ["world.", "world "] {
        assert!(
            matches!(
                世界のディレクトリ名::生成する(名前),
                Err(アセット配置エラー::世界のディレクトリ名が点か空白で終わる(_))
            ),
            "拒まれるべき名前が受理された: {名前}"
        );
    }
}
