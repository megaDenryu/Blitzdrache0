//! 世界のディレクトリ名の検証。受け取るのは綴り、返すのは1つの通常のディレクトリ名として使えるかの成否である。
//!
//! 対象環境はWindowsであり、そこで使えない綴りを構築の時点で拒む。拒む理由は条件ごとに違うため、条件ごとに書く。

use super::super::error::アセット配置エラー;

/// Windowsが装置の名前として予約している綴り。拡張子を付けても装置として解釈されるため、点より前だけを見て突き合わせる。
const 予約された装置の名前: [&str; 22] = [
    "CON", "PRN", "AUX", "NUL", "COM1", "COM2", "COM3", "COM4", "COM5", "COM6", "COM7", "COM8", "COM9", "LPT1", "LPT2", "LPT3", "LPT4", "LPT5",
    "LPT6", "LPT7", "LPT8", "LPT9",
];

/// Windowsのファイル名に使えない記号。コロンを含むのが要点であり、理由は`使えない記号を含まないことを確かめる`に書いた。
const 使えない記号: [char; 7] = [':', '*', '?', '"', '<', '>', '|'];

pub(super) fn 一つの通常のディレクトリ名であることを確かめる(名前: &'static str) -> Result<(), アセット配置エラー> {
    空でないことを確かめる(名前)?;
    区切りを含まないことを確かめる(名前)?;
    場所を指す綴りでないことを確かめる(名前)?;
    使えない記号を含まないことを確かめる(名前)?;
    制御文字を含まないことを確かめる(名前)?;
    予約された装置の名前でないことを確かめる(名前)?;
    点か空白で終わらないことを確かめる(名前)
}

/// 空の綴りを拒むのは、連結してもルートそのものを指すことになり、世界のディレクトリを1つも作らない生成が黙って成功するためである。
fn 空でないことを確かめる(名前: &'static str) -> Result<(), アセット配置エラー> {
    if 名前.is_empty() {
        return Err(アセット配置エラー::世界のディレクトリ名が空である);
    }
    Ok(())
}

/// 区切りを拒むのは、この型が名乗る「ソースルートの直下の1つのディレクトリ」が、区切りを含む綴りでは複数段の場所に
/// なるためである。斜線と逆斜線の両方を見るのは、綴りが動く先の環境によらず1段であることを保つためである。
fn 区切りを含まないことを確かめる(名前: &'static str) -> Result<(), アセット配置エラー> {
    if 名前.contains('/') || 名前.contains('\\') {
        return Err(アセット配置エラー::世界のディレクトリ名が区切りを含む(名前));
    }
    Ok(())
}

/// 今の場所と上の場所を指す綴りを拒むのは、連結してもディレクトリが増えず、上を指す綴りではソースルートの外へ出るためである。
fn 場所を指す綴りでないことを確かめる(名前: &'static str) -> Result<(), アセット配置エラー> {
    if 名前 == "." || 名前 == ".." {
        return Err(アセット配置エラー::世界のディレクトリ名が場所を指す綴りである(名前));
    }
    Ok(())
}

/// 注意: コロンを拒むことがこの検証の要点である。Windowsの連結は、接頭辞を持つ成分が基準の側を丸ごと置き換えるため、
/// `C:escape`のような綴りを受理すると、連結の結果がソースルートの下から離れて「直下の1つのディレクトリ」が崩れる。
/// 残りの記号はWindowsがファイル名に使えないため、受理してもディレクトリを作る段で失敗が遅れて現れる。
fn 使えない記号を含まないことを確かめる(名前: &'static str) -> Result<(), アセット配置エラー> {
    match 名前.chars().find(|文字| 使えない記号.contains(文字)) {
        Some(文字) => Err(アセット配置エラー::世界のディレクトリ名が使えない記号を含む { 名前, 記号: 文字 }),
        None => Ok(()),
    }
}

/// 制御文字を拒むのは、Windowsのファイル名に使えないうえ、綴りとして人が読めず、失敗の報せにも現れないためである。
fn 制御文字を含まないことを確かめる(名前: &'static str) -> Result<(), アセット配置エラー> {
    if 名前.chars().any(char::is_control) {
        return Err(アセット配置エラー::世界のディレクトリ名が制御文字を含む(名前));
    }
    Ok(())
}

/// 予約された装置の名前を拒むのは、その名前のディレクトリをWindowsが作れず、生成の段になって初めて失敗するためである。
/// 大文字と小文字を区別せず、点より前だけを見る。
fn 予約された装置の名前でないことを確かめる(名前: &'static str) -> Result<(), アセット配置エラー> {
    let 点より前 = 名前.split('.').next().unwrap_or(名前);
    if 予約された装置の名前.iter().any(|予約| 点より前.eq_ignore_ascii_case(予約)) {
        return Err(アセット配置エラー::世界のディレクトリ名が予約された装置の名前である(名前));
    }
    Ok(())
}

/// 点と空白で終わる綴りを拒むのは、Windowsがそれらを黙って落として別の名前のディレクトリを作るためである。
/// 書いた名前と現物の名前が食い違うと、読む側が同じ綴りで開けない。
fn 点か空白で終わらないことを確かめる(名前: &'static str) -> Result<(), アセット配置エラー> {
    if 名前.ends_with('.') || 名前.ends_with(' ') {
        return Err(アセット配置エラー::世界のディレクトリ名が点か空白で終わる(
            名前,
        ));
    }
    Ok(())
}
