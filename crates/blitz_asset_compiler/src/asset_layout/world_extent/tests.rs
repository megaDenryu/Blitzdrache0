use super::*;

#[test]
fn 偶数個の世界を原点中心へ置く() {
    let Ok(広がり) = 世界の広がり::生成する(80, 100) else {
        panic!("試験用の世界の広がりを作れなかった");
    };
    assert_eq!(広がり.東の最小座標(), -40);
    assert_eq!(広がり.東の最大座標(), 39);
    assert_eq!(広がり.南の最小座標(), -50);
    assert_eq!(広がり.南の最大座標(), 49);
    assert_eq!(広がり.チャンク総数(), 8_000);
}

#[test]
fn 零の方向を役割ごとの型付きエラーにする() {
    assert_eq!(世界の広がり::生成する(0, 1), Err(世界の広がりエラー::東西チャンク数が零));
    assert_eq!(世界の広がり::生成する(1, 0), Err(世界の広がりエラー::南北チャンク数が零));
}
