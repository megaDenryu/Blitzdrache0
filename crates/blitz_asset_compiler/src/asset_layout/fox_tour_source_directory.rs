//! 場所巡りの世界のソース一式の置き場。世界のソースディレクトリを包み、この世界だけが持つファイル名の綴りと、
//! 座標からアセット名とファイル名を導く規則を足す。
//!
//! ライブラリに置くのは、この置き場を3者が読むためである。乱数の種からソースを書き出す生成器、そのソースを
//! 実行時形式へ焼くコンパイラ、遊ぶ前にどの種の世界かを見せる開発ツールが同じファイルを指す。綴りを写しで持つと、
//! 食い違ったときに「ファイルが無い」という遠い場所の失敗になる。
//!
//! 置き場のパスは包んだ世界のソースディレクトリが1回だけ所有し、台帳の置き場として渡すときも借用で貸す。

use blitz_engine::チャンク座標;
use std::ffi::OsStr;
use std::path::Path;

mod cleanup;
mod seed;
#[cfg(test)]
mod seed_tests;

use super::error::アセット配置エラー;
use super::height_grid_file::高さ格子のファイル;
use super::source_root::ソースルート;
use super::world_directory_name::世界のディレクトリ名;
use super::world_source_directory::世界のソースディレクトリ;
use crate::generation_ledger::生成の出力ルート;

const ディレクトリ名の綴り: &str = "fox_tour_world";
const 目印のバイナリファイル名: &str = "destination_marker.bin";
const 目印の文書ファイル名: &str = "destination_marker.gltf";

/// 生成に使った乱数の種を書き出すファイルの名前。書き手も読み手もこの1つを見る。
const 種を書き出すファイル名: &str = "map_seed.txt";

const 高さ格子の拡張子つきの綴り: &str = ".heightgrid";

#[repr(transparent)]
pub struct 場所巡りの世界のソースディレクトリ(世界のソースディレクトリ);

impl 場所巡りの世界のソースディレクトリ {
    pub fn ディレクトリ名() -> Result<世界のディレクトリ名, アセット配置エラー> {
        世界のディレクトリ名::生成する(ディレクトリ名の綴り)
    }

    pub fn この世界のディレクトリ名か(候補: &OsStr) -> bool {
        候補 == ディレクトリ名の綴り
    }

    /// 置き場を開くだけで、ディレクトリは作らない。読むだけの呼び出し側はこちらを通る。
    pub fn ソースルートの下を開く(ソースルート: &ソースルート) -> Result<Self, アセット配置エラー> {
        Ok(Self(ソースルート.世界のソースディレクトリ(Self::ディレクトリ名()?)))
    }

    pub fn ソースルートの下に作る(ソースルート: &ソースルート) -> Result<Self, アセット配置エラー> {
        Ok(Self(Self::ソースルートの下を開く(ソースルート)?.0.作ってから開く()?))
    }

    /// チャンク1つを指す安定IDの綴り。目録へ載せる名前と高さ格子のファイル名がこの1つから導かれる。
    pub fn チャンクのアセット名(座標: チャンク座標) -> String {
        format!("fox_tour_x{}_z{}", 座標.x(), 座標.z())
    }

    /// 目録が書く、目録ソースの置き場からの相対のファイル名。
    pub fn 高さ格子の相対ファイル名(座標: チャンク座標) -> String {
        format!("{}{高さ格子の拡張子つきの綴り}", Self::チャンクのアセット名(座標))
    }

    pub fn 高さ格子のファイル(&self, 座標: チャンク座標) -> 高さ格子のファイル {
        高さ格子のファイル::パスから作る(self.0.直下のファイルのパス(&Self::高さ格子の相対ファイル名(座標)))
    }

    pub fn 目録ソースを書き出す(&self, 本文: &str) -> Result<(), アセット配置エラー> {
        self.0.チャンク目録ソースへ書き込む(本文.as_bytes())
    }

    pub fn 目印の柱を書き出す(&self, バッファのバイト列: &[u8], 文書の綴り: &str) -> Result<(), アセット配置エラー> {
        self.0.直下へ書き込む(目印のバイナリファイル名, バッファのバイト列)?;
        self.0.直下へ書き込む(目印の文書ファイル名, 文書の綴り.as_bytes())
    }

    /// 目印の文書が自分の中で参照するバッファのファイル名。文書の綴りを組む側へ渡す。
    pub fn 目印のバイナリの参照名() -> &'static str {
        目印のバイナリファイル名
    }

    /// 生成台帳の置き場としてのこの置き場。台帳の読み書きは生成の出力ルートの側が担う。
    pub fn 台帳の置き場(&self) -> &生成の出力ルート {
        self.0.台帳の置き場()
    }

    pub fn 表示の綴り(&self) -> std::path::Display<'_> {
        self.0.表示の綴り()
    }

    pub fn ファイル走査へ貸すディレクトリ(&self) -> &Path {
        self.0.ファイル走査へ貸すディレクトリ()
    }
}
