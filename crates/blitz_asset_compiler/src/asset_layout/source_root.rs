//! ソースルート: 世界ごとのソースディレクトリが並ぶ親ディレクトリを表す型と、その下の目録ソースの置き場。
//!
//! 目録ソースの置き場を別の型にするのは、目録の1行が置き場からの相対でチャンクのソースを指すためである。
//! 基準のディレクトリを裸のパスで持ち回ると、どのディレクトリからの相対なのかが呼び出し側の記憶になる。

use std::path::{Path, PathBuf};

use super::error::アセット配置エラー;
use super::world_directory_name::世界のディレクトリ名;
use super::world_source_directory::世界のソースディレクトリ;
use crate::chunk_directory_source::{チャンク目録ソース, チャンク目録ソースを読み込む};
use crate::error::アセットコンパイルエラー;
use crate::source_asset_paths::ソースアセットの相対パス;

#[repr(transparent)]
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ソースルート(PathBuf);

impl ソースルート {
    pub fn 生成する(ディレクトリ: PathBuf) -> Self {
        Self(ディレクトリ)
    }

    /// 別のプロセスの引数として渡すためのディレクトリ。
    ///
    /// 注意: この型が生のパスへ戻る唯一の口である。プロセスの引数は綴りでしか渡せないため、型で運べるのは
    /// この呼び出しの手前までである。ソースのファイルを組み立てる用途でこれを呼んではならない。
    /// 人へ見せる行は`表示の綴り`を通る。
    pub fn プロセスの引数へ渡すディレクトリ(&self) -> &Path {
        &self.0
    }

    /// 人へ見せるための綴り。報告の行がこの口を通り、引数のための生値化と使い分ける。
    pub fn 表示の綴り(&self) -> std::path::Display<'_> {
        self.0.display()
    }

    /// ファイルの走査へ渡すためのディレクトリ。走査は綴りを1件ずつ受け取る形を取れず、木をたどる起点を要る。
    /// 綴りを組み立てる用途でこれを呼んではならない。ソースの実パスは`宣言の相対パスが指すソース`が組む。
    pub fn ファイル走査へ貸すディレクトリ(&self) -> &Path {
        &self.0
    }

    pub(super) fn 世界のソースディレクトリ(&self, 名前: 世界のディレクトリ名) -> 世界のソースディレクトリ {
        世界のソースディレクトリ::ソースルートの下に作る(&self.0, 名前)
    }

    /// 宣言1件がソースルートからの相対で指すソースの実パス。世界のディレクトリをまたぐ宣言もあるため、
    /// 1つのディレクトリ名でなく相対パスを受け取る。
    pub fn 宣言の相対パスが指すソース(&self, 相対パス: ソースアセットの相対パス) -> PathBuf {
        相対パス.ルートの下のファイル(&self.0)
    }

    /// 宣言1件のソースを収めるディレクトリ。取得したソースを書き込む前に作る側が読む。
    pub fn 宣言の相対パスが指すソースを収める場所(&self, 相対パス: ソースアセットの相対パス) -> PathBuf {
        相対パス.ルートの下の収める場所(&self.0)
    }

    /// ソースルートの直下に置く、世界のディレクトリでない置き場のパス。地表層のタイル画像の置き場がこれである。
    /// ディレクトリ名の綴りは呼び出す置き場の型が自分の中に持ち、その1箇所からだけここへ渡る。
    pub fn 直下の置き場のパス(&self, ディレクトリ名: &str) -> PathBuf {
        self.0.join(ディレクトリ名)
    }

    pub fn 世界のチャンク目録ソースの置き場(
        &self, 名前: 世界のディレクトリ名
    ) -> チャンク目録ソースの置き場 {
        let 世界のディレクトリ = self.世界のソースディレクトリ(名前);
        チャンク目録ソースの置き場 {
            目録ソース: 世界のディレクトリ.チャンク目録ソースのパス(),
            世界のディレクトリ,
        }
    }
}

/// チャンク目録ソース1本と、その隣に並ぶチャンクのソースを解決する置き場。
pub struct チャンク目録ソースの置き場 {
    世界のディレクトリ: 世界のソースディレクトリ,
    目録ソース: PathBuf,
}

impl チャンク目録ソースの置き場 {
    /// 目録ソースの読み解きの破れをそのまま返すのは、その誤りが読めなかったファイルを自分で名指しており、
    /// 置き場の側から重ねて名指す必要が無いためである。
    pub fn 目録を読み込む(&self) -> Result<チャンク目録ソース, アセットコンパイルエラー> {
        チャンク目録ソースを読み込む(&self.目録ソース)
    }

    /// 目録の1行が置き場からの相対で指すチャンクのソース。存在しなければ失敗させ、無いまま焼き進めない。
    pub fn 目録が指すチャンクのソース(&self, 相対パス: &Path) -> Result<PathBuf, アセット配置エラー> {
        let パス = self.世界のディレクトリ.直下の相対パスが指すファイル(相対パス);
        if パス.is_file() {
            Ok(パス)
        } else {
            Err(アセット配置エラー::目録が指すチャンクのソースが無い { パス })
        }
    }

    pub fn 目録ソースの表示の綴り(&self) -> std::path::Display<'_> {
        self.目録ソース.display()
    }
}
