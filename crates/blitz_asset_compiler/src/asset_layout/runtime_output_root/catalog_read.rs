//! 実行時カタログを出力ルートから読む。

use super::{実行時カタログのファイル名, 実行時形式の出力ルート};
use crate::asset_layout::アセット配置エラー;
use crate::generation_ledger::マップ生成の乱数の種;
use blitz_engine::{カタログ, 世界の由来, 実行時形式からカタログを読む};

impl 実行時形式の出力ルート {
    pub fn 前回の実行時カタログを読む(&self) -> Option<カタログ> {
        self.実行時カタログを読む().ok()
    }

    pub fn 実行時カタログを読む(&self) -> Result<カタログ, アセット配置エラー> {
        let パス = self.0.直下のファイルのパス(実行時カタログのファイル名);
        let バイト列 = std::fs::read(&パス).map_err(|誤り| アセット配置エラー::ファイルを読めなかった {
            パス: パス.clone(),
            事由: 誤り.to_string(),
        })?;
        実行時形式からカタログを読む(&バイト列).map_err(|誤り| アセット配置エラー::ファイルを読めなかった {
            パス,
            事由: 誤り.to_string(),
        })
    }

    pub fn 世界の乱数の種を読む(&self) -> Result<Option<マップ生成の乱数の種>, アセット配置エラー> {
        Ok(match self.実行時カタログを読む()?.世界の由来() {
            世界の由来::種から生成した { 乱数の種, .. } => Some(マップ生成の乱数の種::生成する(乱数の種.値())),
            世界の由来::生成による由来を持たない => None,
        })
    }
}
