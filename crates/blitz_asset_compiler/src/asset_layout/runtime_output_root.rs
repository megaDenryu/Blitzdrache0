//! 実行時形式の出力ルート: 1つの世界の実行時形式一式を置くディレクトリを表す型。カタログ・チャンク目録・アセットの
//! ファイル名の綴りと、それらの書き出しと読み戻しを持つ。
//!
//! 綴りを型の中へ閉じるのは、拡張子やカタログの名前の写しが呼び出し側へ散ると、書く側と読む側で食い違ったときに
//! 「前回のカタログが読めないので全部焼き直す」という無言の劣化になるためである。
//!
//! 置き場のパスは包んだ生成の出力ルートが1回だけ所有する。台帳の置き場として渡すときも借用で貸し、複製を作らない。

use blitz_engine::アセットID;
use std::path::PathBuf;

use super::error::アセット配置エラー;
use crate::generation_ledger::生成の出力ルート;

mod catalog_read;
mod cleanup;

const 実行時カタログのファイル名: &str = "catalog.blitzcatalog";
const 実行時目録のファイル名: &str = "chunk_directory.blitzchunks";
const アセットの拡張子つきの綴り: &str = ".blitzasset";

#[repr(transparent)]
pub struct 実行時形式の出力ルート(生成の出力ルート);

impl 実行時形式の出力ルート {
    pub fn 実行時カタログを指すパスか(パス: &std::path::Path) -> bool {
        パス.file_name().is_some_and(|名前| 名前 == 実行時カタログのファイル名)
    }

    pub fn 作る(ディレクトリ: PathBuf) -> Result<Self, アセット配置エラー> {
        let 置き場 = Self::ディレクトリを作らずに指す(ディレクトリ);
        置き場.0.ディレクトリを作る()?;
        Ok(置き場)
    }

    pub fn アセットの出力パス(&self, 安定id: &アセットID) -> PathBuf {
        self.0.直下のファイルのパス(&Self::アセットのファイル名(安定id))
    }

    /// アセット1件を書き出し、カタログが実行時パスとして持つファイル名を返す。ファイル名を1回だけ組んで
    /// 書き出しと戻り値の両方に使う。
    pub fn アセットを書き出す(&self, 安定id: &アセットID, バイト列: &[u8]) -> Result<PathBuf, アセット配置エラー> {
        let ファイル名 = Self::アセットのファイル名(安定id);
        let パス = self.直下へ書き込む(&ファイル名, バイト列)?;
        println!("[compile_assets] {}: {}バイト", パス.display(), バイト列.len());
        Ok(PathBuf::from(ファイル名))
    }

    fn アセットのファイル名(安定id: &アセットID) -> String {
        format!("{安定id}{アセットの拡張子つきの綴り}")
    }

    /// 前回の実行時カタログ。読めなければ値なしを返す。初回の生成にはカタログが無く、
    /// 壊れたカタログを読み違えるよりも全部焼き直すほうが安全である。
    pub fn 実行時カタログを書き出す(&self, バイト列: &[u8]) -> Result<(), アセット配置エラー> {
        let パス = self.直下へ書き込む(実行時カタログのファイル名, バイト列)?;
        println!("[compile_assets] {}: {}バイト", パス.display(), バイト列.len());
        Ok(())
    }

    pub fn チャンク目録を書き出す(&self, バイト列: &[u8], チャンク数: usize) -> Result<(), アセット配置エラー> {
        let パス = self.直下へ書き込む(実行時目録のファイル名, バイト列)?;
        println!("[compile_assets] {}: {}バイト({}チャンク)", パス.display(), バイト列.len(), チャンク数);
        Ok(())
    }

    /// ディレクトリを作らずに、その置き場を指すだけの口。書き出しをせず役割として保持するだけの側が通る。
    ///
    /// 注意: `作る`と分けるのは、包むだけの構築が失敗も副作用も持ってはならないためである。指定を組むだけで
    /// ディレクトリを作ると、生成器を1度も起こせなかった実行が空のディレクトリを残す。
    /// ディレクトリの実在を引き受けるのは、そこへ書き出す側が通る`作る`だけである。
    pub fn ディレクトリを作らずに指す(ディレクトリ: PathBuf) -> Self {
        Self(生成の出力ルート::生成する(ディレクトリ))
    }

    /// 別のプロセスの引数として渡すためのディレクトリ。生のパスへ戻る唯一の口であり、包んだ生成の出力ルートが持つ。
    pub fn プロセスの引数へ渡すディレクトリ(&self) -> &std::path::Path {
        self.0.プロセスの引数へ渡すディレクトリ()
    }

    /// 人へ見せるための綴り。報告の行がこの口を通り、引数のための生値化と使い分ける。
    pub fn 表示の綴り(&self) -> std::path::Display<'_> {
        self.0.表示の綴り()
    }

    /// 生成台帳の置き場としてのこの置き場。台帳の読み書きは生成の出力ルートの側が担う。
    pub fn 台帳の置き場(&self) -> &生成の出力ルート {
        &self.0
    }

    /// この置き場がファイルへ書く唯一の口。書いた先を返すのは、報せの行がパスを載せるためである。
    fn 直下へ書き込む(&self, ファイル名: &str, バイト列: &[u8]) -> Result<PathBuf, アセット配置エラー> {
        let パス = self.0.直下のファイルのパス(ファイル名);
        std::fs::write(&パス, バイト列).map_err(|誤り| アセット配置エラー::ファイルへ書き出せなかった {
            パス: パス.clone(),
            事由: 誤り.to_string(),
        })?;
        Ok(パス)
    }
}
