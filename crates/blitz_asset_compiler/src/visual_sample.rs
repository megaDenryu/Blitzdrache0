//! 高さ格子と材質見本の立体と小物の原型から、目視見本1チャンク分の実行時シーンを焼く。
//!
//! 見本の集落と違うのは3つである。1つは金属度と粗さの水準ごとに並べた球を1つの固定物として据えることであり、
//! 1つは地面のベースカラーを土と草の実測に近い暗さへ取ることであり、もう1つはチャンクの外へ遠景地面を広げることである。球の映り込みと地面の明るさの両方を
//! オーナーが目で確かめる世界であるため、既定の白い地面では地面が飽和して球の比較にならない。
//!
//! 地面の焼き方と群の組み立て方は地形・見本の集落の工程をそのまま呼ぶ。写しを持つと、同じ地面から別の三角形が出たり、
//! 同じ宣言から別の配置が出たりして、どちらが正かが決まらなくなる。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Ic-3bの実装」

mod fixed_objects;
mod scene;

use blitz_engine::{アセットID, カタログ, シーンを実行時形式へ格納する, チャンク座標};

use crate::compile::{コンパイル済みシーン, メタデータを集計する};
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子を読み込む;
use crate::texture_storage::テクスチャ格納方針;
use crate::village::小物群の指定;

/// この世界が地面の上へ据えるものの指定。材質見本の立体と遠景地面は1つずつ、小物の群は種の数だけ持つ。
/// 群の一覧を借用でなく所有で持つのは、宣言から指定へ写す工程がその場で作った一覧をそのまま渡せるようにするためである。
pub struct 目視見本の指定 {
    pub 材質見本の立体id: アセットID,
    pub 遠景地面id: アセットID,
    pub 群一覧: Vec<小物群の指定>,
}

pub fn 目視見本チャンクをコンパイルする(
    カタログ: &カタログ,
    id: &アセットID,
    所有チャンク: チャンク座標,
    指定: &目視見本の指定,
    方針: テクスチャ格納方針,
) -> Result<コンパイル済みシーン, アセットコンパイルエラー> {
    let パス = カタログ
        .パスを参照する(id)
        .ok_or_else(|| アセットコンパイルエラー::カタログ未登録(id.clone()))?;
    let 格子 = 高さ格子を読み込む(パス)?;
    let シーン = scene::組み立てる(カタログ, &格子, 所有チャンク, パス.to_path_buf(), 指定, 方針)?;
    let メタデータ = メタデータを集計する(&シーン)?;
    let 実行時バイト列 = シーンを実行時形式へ格納する(&シーン)?;
    Ok(コンパイル済みシーン {
        実行時バイト列,
        ソース依存一覧: シーン.参照ファイル一覧,
        メタデータ,
    })
}
