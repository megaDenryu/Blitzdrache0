//! 組み立てに使う部品一式: 宣言された部品を、部品IDと原型の安定IDとソースの置き場の3つ組で持つ型。
//!
//! 3つを1つの型が持つのは、展開が部品IDで答えを返し、原型の読み込みが安定IDを要り、カタログの組み上げが
//! ソースの置き場を要るためである。3つが別々の並びだと、並びの順が食い違ったときに別の部品の原型が焼かれる。
//!
//! 部品IDをファイル名から作るのは、カタログの読み込み係と同じ決め方だからである。決め方が2つあると、
//! 展開が返した部品IDでこの型を引けない組み合わせが生まれる。
//!
//! 並びと散布の両方がこの型を使う。どちらも「宣言された部品でカタログを組み、展開が返した部品IDから原型を引く」
//! という同じ仕事をするため、写しを持つと片方だけ直した食い違いが出る。

use std::path::{Path, PathBuf};

use blitz_assembly::{部品ID, 部品カタログ};
use blitz_engine::アセットID;

use crate::error::アセットコンパイルエラー;
use crate::loader::{部品のglTFのファイル, 部品カタログの読み込み係};
use crate::part_row::部品で組んだ並びのコンパイルエラー;
use crate::scene_compiler::ソースアセットのコンパイル係;

/// 部品1件の3つ組。
struct 部品と原型の対応 {
    部品の識別子: 部品ID,
    原型の安定id: アセットID,
    ソースの置き場: PathBuf,
}

pub(crate) struct 組み立てに使う部品一式 {
    対応一覧: Vec<部品と原型の対応>,
}

impl 組み立てに使う部品一式 {
    /// 宣言された安定IDの並びから、部品IDとソースの置き場を解決する。
    pub(crate) fn 宣言から読み取る(
        コンパイル係: &ソースアセットのコンパイル係<'_>,
        安定id一覧: &[アセットID],
    ) -> Result<Self, アセットコンパイルエラー> {
        let mut 対応一覧 = Vec::with_capacity(安定id一覧.len());
        for 安定id in 安定id一覧 {
            let 置き場 = コンパイル係.安定idが指すソースのパスを参照する(安定id)?.to_path_buf();
            let 識別子 = 部品のglTFのファイル::生成する(&置き場)
                .部品idを作る()
                .map_err(|誤り| 読めなかった(&置き場, 誤り))?;
            対応一覧.push(部品と原型の対応 {
                部品の識別子: 識別子,
                原型の安定id: 安定id.clone(),
                ソースの置き場: 置き場,
            });
        }
        Ok(Self { 対応一覧 })
    }

    /// 全件を読んでカタログを組み上げる。対の相手が揃わない部品はここで型付きエラーになる。
    pub(crate) fn カタログを組み上げる(&self) -> Result<部品カタログ, アセットコンパイルエラー> {
        let 置き場一覧: Vec<PathBuf> = self.対応一覧.iter().map(|対応| 対応.ソースの置き場.clone()).collect();
        let カタログ = 部品カタログの読み込み係::パスの並びから生成する(&置き場一覧)
            .組み上げる()
            .map_err(部品で組んだ並びのコンパイルエラー::部品カタログを組めない)?;
        Ok(カタログ)
    }

    /// 部品の識別子とソースの置き場を宣言の順に数え上げる。カタログが持たない部品ごとの実体(境界箱)を読む工程が使う。
    pub(crate) fn 部品とソースの置き場を数え上げる(&self) -> impl Iterator<Item = (&部品ID, &Path)> {
        self.対応一覧.iter().map(|対応| (&対応.部品の識別子, 対応.ソースの置き場.as_path()))
    }

    /// 展開が据えた部品IDから、その部品の原型を焼くための安定IDを引く。
    pub(crate) fn 原型の安定idを引く(&self, 識別子: &部品ID) -> Result<&アセットID, アセットコンパイルエラー> {
        let 対応 = self.対応一覧.iter().find(|対応| &対応.部品の識別子 == 識別子).ok_or_else(|| {
            部品で組んだ並びのコンパイルエラー::据えた部品が宣言に無い {
                部品の綴り: 識別子.綴り().to_string(),
            }
        })?;
        Ok(&対応.原型の安定id)
    }
}

fn 読めなかった(置き場: &Path, 誤り: crate::loader::部品の読み取りエラー) -> アセットコンパイルエラー {
    部品で組んだ並びのコンパイルエラー::部品カタログを組めない(
        crate::loader::部品カタログの読み込みエラー::部品を読めない {
            パス: 置き場.display().to_string(),
            誤り,
        },
    )
    .into()
}
