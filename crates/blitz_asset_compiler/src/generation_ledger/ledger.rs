//! 生成台帳の実体。見出しとチャンクごとの内容ハッシュを持ち、チャンク1つを焼き直すか据え置くかの判定と、
//! 生成の出力ルート直下への読み書きを担う。
//!
//! 置き場を生成の出力ルートの直下に固定するのは、台帳が生成物と同じ寿命を持つためである。カタログへは載せない。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use blitz_engine::チャンク座標;

use super::content_hash::内容ハッシュ;
use super::error::生成台帳エラー;
use super::heading::生成台帳の見出し;
use super::text_format::{台帳のテキストを組み立てる, 台帳のテキストを解析する};

const 台帳のファイル名: &str = "generation_ledger.txt";

/// チャンク1つを焼き直すか据え置くかの判定。据え置く枝が内容ハッシュを持つのは、
/// 次の台帳へそのまま記録し直すためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum チャンクの焼き直し判定 {
    据え置く { 内容ハッシュ: 内容ハッシュ },
    焼き直す,
}

pub struct 生成台帳 {
    見出し: 生成台帳の見出し,
    チャンクごとの内容ハッシュ: BTreeMap<(i32, i32), 内容ハッシュ>,
}

impl 生成台帳 {
    pub fn 見出しを与えて空を作る(見出し: 生成台帳の見出し) -> Self {
        Self {
            見出し,
            チャンクごとの内容ハッシュ: BTreeMap::new(),
        }
    }

    /// 出力ルート直下の台帳を読む。台帳が無いときと、見出しが今回の生成と食い違うときは空の台帳を返す。
    /// 見出しが違えば記録の1件も使えないため、読めなかったことと区別する必要が無い。
    pub fn 出力ルートから読み込む(
        出力ルート: &Path, 今回の見出し: 生成台帳の見出し
    ) -> Result<Self, 生成台帳エラー> {
        let パス = 台帳のパスを作る(出力ルート);
        let Ok(テキスト) = std::fs::read_to_string(&パス) else {
            return Ok(Self::見出しを与えて空を作る(今回の見出し));
        };
        let 中身 = 台帳のテキストを解析する(&テキスト)?;
        if 中身.見出し != 今回の見出し {
            return Ok(Self::見出しを与えて空を作る(今回の見出し));
        }
        Ok(Self {
            見出し: 今回の見出し,
            チャンクごとの内容ハッシュ: 中身.チャンクごとの内容ハッシュ,
        })
    }

    pub fn 出力ルートへ書き出す(&self, 出力ルート: &Path) -> Result<(), 生成台帳エラー> {
        let パス = 台帳のパスを作る(出力ルート);
        let テキスト = 台帳のテキストを組み立てる(self.見出し, &self.チャンクごとの内容ハッシュ);
        std::fs::write(&パス, テキスト).map_err(|誤り| 生成台帳エラー::ファイルの書き出しに失敗した {
            パス,
            事由: 誤り.to_string(),
        })
    }

    pub fn 内容ハッシュを記録する(&mut self, チャンク: チャンク座標, 内容ハッシュ: 内容ハッシュ) {
        self.チャンクごとの内容ハッシュ.insert((チャンク.x(), チャンク.z()), 内容ハッシュ);
    }

    /// チャンク1つを焼き直すかを判定する。据え置けるのは、生成物が現に在り、内容を照合するファイルの内容ハッシュが
    /// 台帳の記録と一致するときだけである。ソースを書き出す側では2つのパスが同じファイルを指す。
    pub fn チャンクを焼き直すかを判定する(
        &self,
        チャンク: チャンク座標,
        内容を照合するファイル: &Path,
        揃っているべき生成物: &Path,
    ) -> Result<チャンクの焼き直し判定, 生成台帳エラー> {
        if !揃っているべき生成物.is_file() || !内容を照合するファイル.is_file() {
            return Ok(チャンクの焼き直し判定::焼き直す);
        }
        let 現在の内容ハッシュ = 内容ハッシュ::ファイルの中身から求める(内容を照合するファイル)?;
        match self.チャンクごとの内容ハッシュ.get(&(チャンク.x(), チャンク.z())) {
            Some(記録) if *記録 == 現在の内容ハッシュ => Ok(チャンクの焼き直し判定::据え置く {
                内容ハッシュ: 現在の内容ハッシュ,
            }),
            _ => Ok(チャンクの焼き直し判定::焼き直す),
        }
    }
}

fn 台帳のパスを作る(出力ルート: &Path) -> PathBuf {
    出力ルート.join(台帳のファイル名)
}
