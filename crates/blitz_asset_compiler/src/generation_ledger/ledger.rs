//! 生成台帳の実体。見出しとチャンクごとの内容ハッシュを持ち、チャンク1つを焼き直すか据え置くかを判定する。
//!
//! この型はパスもファイル操作も持たない。台帳をどこへ置くかと、その置き場での読み書きは`生成の出力ルート`が持つ。
//! 判定に生成物の在り処でなく「揃っているか」の真偽を受け取るのも同じ理由であり、在り処を知っているのは
//! 生成物の置き場を表す型の側だからである。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

use std::collections::BTreeMap;

use blitz_engine::チャンク座標;

use super::content_hash::内容ハッシュ;
use super::error::生成台帳エラー;
use super::heading::生成台帳の見出し;
use super::ledger_text::生成台帳の本文;
use super::output_root::生成の出力ルート;

/// チャンク1つを焼き直すか据え置くかの判定。据え置く枝が内容ハッシュを持つのは、
/// 次の台帳へそのまま記録し直すためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum チャンクの焼き直し判定 {
    据え置く { 内容ハッシュ: 内容ハッシュ },
    焼き直す,
}

pub struct 生成台帳 {
    見出し: 生成台帳の見出し,
    チャンクごとの内容ハッシュ: BTreeMap<チャンク座標, 内容ハッシュ>,
}

impl 生成台帳 {
    pub fn 見出しを与えて空を作る(見出し: 生成台帳の見出し) -> Self {
        Self {
            見出し,
            チャンクごとの内容ハッシュ: BTreeMap::new(),
        }
    }

    /// 出力ルートの台帳を読む。台帳が無いとき・読めないとき・見出しが今回の生成と食い違うときは空の台帳を返す。
    /// この3つを区別しないのは、どれも記録を1件も使えない点で同じであり、空の台帳は全部を焼き直す側へ倒れるためである。
    /// 読めないことを失敗にすると、台帳の形式を変えた後の1回目の生成が古い台帳のせいで止まる。
    pub fn 出力ルートから読み込む(出力ルート: &生成の出力ルート, 今回の見出し: 生成台帳の見出し) -> Self {
        let 空の台帳 = || Self::見出しを与えて空を作る(今回の見出し);
        let Some(本文) = 出力ルート.台帳の本文を読む() else {
            return 空の台帳();
        };
        let Ok(中身) = 本文.解析する() else {
            return 空の台帳();
        };
        if 中身.見出し != 今回の見出し {
            return 空の台帳();
        }
        Self {
            見出し: 今回の見出し,
            チャンクごとの内容ハッシュ: 中身.チャンクごとの内容ハッシュ,
        }
    }

    pub fn 出力ルートへ書き出す(&self, 出力ルート: &生成の出力ルート) -> Result<(), 生成台帳エラー> {
        出力ルート.台帳の本文を書く(&生成台帳の本文::組み立てる(self.見出し, &self.チャンクごとの内容ハッシュ))
    }

    pub fn 内容ハッシュを記録する(&mut self, チャンク: チャンク座標, 内容ハッシュ: 内容ハッシュ) {
        self.チャンクごとの内容ハッシュ.insert(チャンク, 内容ハッシュ);
    }

    /// チャンク1つを焼き直すかを判定する。据え置けるのは、生成物が現に揃っていて、今の材料の内容ハッシュが
    /// 台帳の記録と一致するときだけである。材料がまだ無いときは`None`を渡す。
    pub fn チャンクを焼き直すかを判定する(
        &self,
        チャンク: チャンク座標,
        今の材料の内容ハッシュ: Option<内容ハッシュ>,
        生成物が揃っているか: bool,
    ) -> チャンクの焼き直し判定 {
        let Some(今の内容ハッシュ) = 今の材料の内容ハッシュ else {
            return チャンクの焼き直し判定::焼き直す;
        };
        if !生成物が揃っているか {
            return チャンクの焼き直し判定::焼き直す;
        }
        match self.チャンクごとの内容ハッシュ.get(&チャンク) {
            Some(記録) if *記録 == 今の内容ハッシュ => チャンクの焼き直し判定::据え置く {
                内容ハッシュ: 今の内容ハッシュ,
            },
            _ => チャンクの焼き直し判定::焼き直す,
        }
    }
}
