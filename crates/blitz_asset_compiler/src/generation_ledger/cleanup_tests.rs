//! 種・生成器版の変更だけが出力一式の全消去を要求することの検査。

#![allow(clippy::unwrap_used)]

use super::{
    content_hash::内容ハッシュ,
    generator_version::生成器の版,
    heading::生成台帳の見出し,
    ledger::生成台帳,
    map_seed::{マップ生成の乱数の種, 種の由来},
    output_root::生成の出力ルート,
    read_result::生成台帳の読み込み結果,
};

#[test]
fn 種の変更は全消去を要求する() {
    let 前回 = 種を選んだ見出しを作る(1);
    let 今回 = 種を選んだ見出しを作る(2);
    assert!(読み込み結果を作る(前回, 今回, "seed").種または生成器の版が変わったか());
}

#[test]
fn 生成器の版の変更は全消去を要求する() {
    let 前回 = 版を選んだ見出しを作る(1, "same");
    let 今回 = 版を選んだ見出しを作る(2, "same");
    assert!(読み込み結果を作る(前回, 今回, "version").種または生成器の版が変わったか());
}

#[test]
fn 種と版が同じなら他の見出しが変わっても全消去しない() {
    let 前回 = 版を選んだ見出しを作る(1, "old");
    let 今回 = 版を選んだ見出しを作る(1, "new");
    assert!(!読み込み結果を作る(前回, 今回, "unchanged").種または生成器の版が変わったか());
}

fn 種を選んだ見出しを作る(種: u32) -> 生成台帳の見出し {
    見出しを作る(種の由来::種から焼いた(マップ生成の乱数の種::生成する(種)), 1, "same")
}

fn 版を選んだ見出しを作る(版: u32, 焼き方: &str) -> 生成台帳の見出し {
    見出しを作る(種の由来::種を持たない, 版, 焼き方)
}

fn 見出しを作る(種: 種の由来, 版: u32, 焼き方: &str) -> 生成台帳の見出し {
    生成台帳の見出し::読み取った値から組み立てる(
        種,
        生成器の版::生成する(版),
        内容ハッシュ::バイト列から求める(b"generator"),
        内容ハッシュ::バイト列から求める(焼き方.as_bytes()),
    )
}

fn 読み込み結果を作る(
    前回: 生成台帳の見出し, 今回: 生成台帳の見出し, 名前: &str
) -> 生成台帳の読み込み結果 {
    let パス = std::env::temp_dir().join(format!("blitz_ledger_read_{}_{}", std::process::id(), 名前));
    let _ = std::fs::remove_dir_all(&パス);
    let ルート = 生成の出力ルート::生成する(パス.clone());
    ルート.ディレクトリを作る().unwrap();
    生成台帳::見出しを与えて空を作る(前回).出力ルートへ書き出す(&ルート).unwrap();
    let 結果 = 生成台帳::出力ルートから読み込む(&ルート, 今回);
    std::fs::remove_dir_all(パス).unwrap();
    結果
}
