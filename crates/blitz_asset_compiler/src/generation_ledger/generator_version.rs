//! 生成器の版: 世界を焼く規則そのものの版番号。生成台帳の見出しへ入り、版が変われば台帳の記録を1件も信用しない。
//!
//! 注意: 生成規則の定数を1つでも変えたらこの版を上げる。上げないと、増分の鍵が一致したまま中身の違うチャンクが残る。
//! ここでいう生成規則の定数とは、高さを決める式の係数・格子の細かさ・世界の広がり・重なり幅のように、
//! 同じ乱数の種から出る中身を変えうる値のことである。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

use super::error::生成台帳エラー;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct 生成器の版(u32);

impl 生成器の版 {
    pub const fn 生成する(版番号: u32) -> Self {
        Self(版番号)
    }

    pub fn 版番号(self) -> u32 {
        self.0
    }

    pub const fn 世界の生成器の版へ写す(
        self,
    ) -> Result<blitz_engine::世界の生成器の版, blitz_engine::アセット実行時形式エラー> {
        blitz_engine::世界の生成器の版::生成する(self.0)
    }

    pub(super) fn 十進の綴りから復元する(綴り: &str) -> Result<Self, 生成台帳エラー> {
        綴り
            .parse::<u32>()
            .map(Self)
            .map_err(|_| 生成台帳エラー::未対応の版である(綴り.to_string()))
    }
}

/// 現在の生成規則の版。生成規則を変えたときに上げる唯一の値であり、ソースの書き出しと実行時形式のコンパイルの
/// 両方の台帳がこの1つを見る。
///
/// 版2は第6段階の岩の散布で上げた。同じ乱数の種から出るチャンクの中身が変わるためである。
pub const 現在の生成器の版: 生成器の版 = 生成器の版::生成する(2);
