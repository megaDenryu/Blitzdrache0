//! 生成台帳の読み書きと照合で破れうる前提の型付きエラー。台帳はファイルとして残るため、
//! 別形式のテキストを台帳として読み進めないことと、読めなかった事由が呼び出し側へ届くことをここで守る。

use std::path::PathBuf;

use thiserror::Error;

#[derive(Debug, Error)]
pub enum 生成台帳エラー {
    #[error("{}を読めない: {事由}", パス.display())]
    ファイルの読み取りに失敗した { パス: PathBuf, 事由: String },
    #[error("{}へ書き出せない: {事由}", パス.display())]
    ファイルの書き出しに失敗した { パス: PathBuf, 事由: String },
    #[error("{}を作れない: {事由}", パス.display())]
    ディレクトリを作れなかった { パス: PathBuf, 事由: String },
    #[error("{}を削除できない: {事由}", パス.display())]
    出力の削除に失敗した { パス: PathBuf, 事由: String },
    #[error("実行中の生成器の実行ファイルの場所が分からない: {0}")]
    生成器の実行ファイルを特定できない(String),
    #[error("生成台帳の形式宣言が違う: {0}")]
    形式宣言が違う(String),
    #[error("生成台帳の版{0}には対応していない")]
    未対応の版である(String),
    #[error("生成台帳の{行番号}行目を読めない: {内容}")]
    行を読めない { 行番号: usize, 内容: String },
}
