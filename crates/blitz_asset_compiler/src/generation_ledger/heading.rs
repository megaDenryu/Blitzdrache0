//! 生成台帳の見出し: その台帳を書いた生成が何者だったかを表す3つの値である。見出しが今回の生成と1つでも食い違う台帳は、
//! 記録を1件も信用せず空として扱う。増分の鍵のうち、チャンクごとに変わらない部分がここに集まる。
//!
//! 生成器の実行ファイルの内容ハッシュを入れるのは、生成器の版が人の手で上げる値だからである。版を上げ忘れたまま生成規則を
//! 書き換えると、鍵が一致したまま中身の違うチャンクが残る。実行ファイルの中身は規則を書き換えれば必ず変わるため、
//! 上げ忘れをこの値が捕まえる。規則と無関係な再ビルドで実行ファイルが変わった場合は焼き直しが増えるだけであり、
//! 古い生成物を使ってしまう側へは倒れない。

use super::content_hash::内容ハッシュ;
use super::error::生成台帳エラー;
use super::generator_version::{現在の生成器の版, 生成器の版};
use super::map_seed::種の由来;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 生成台帳の見出し {
    種の由来: 種の由来,
    生成器の版: 生成器の版,
    生成器の実行ファイルの内容ハッシュ: 内容ハッシュ,
}

impl 生成台帳の見出し {
    /// 今このプロセスとして走っている生成器から見出しを作る。生成器の版は`現在の生成器の版`だけを読むため、
    /// 呼び出し側が版を選ぶ余地は無い。
    pub fn 実行中の生成器から作る(種の由来: 種の由来) -> Result<Self, 生成台帳エラー> {
        let 実行ファイル =
            std::env::current_exe().map_err(|誤り| 生成台帳エラー::生成器の実行ファイルを特定できない(誤り.to_string()))?;
        Ok(Self {
            種の由来,
            生成器の版: 現在の生成器の版,
            生成器の実行ファイルの内容ハッシュ: 内容ハッシュ::ファイルの中身から求める(&実行ファイル)?,
        })
    }

    pub(super) fn 読み取った値から組み立てる(
        種の由来: 種の由来,
        生成器の版: 生成器の版,
        生成器の実行ファイルの内容ハッシュ: 内容ハッシュ,
    ) -> Self {
        Self {
            種の由来,
            生成器の版,
            生成器の実行ファイルの内容ハッシュ,
        }
    }

    pub(super) fn 種の由来(self) -> 種の由来 {
        self.種の由来
    }

    pub(super) fn 生成器の版(self) -> 生成器の版 {
        self.生成器の版
    }

    pub(super) fn 生成器の実行ファイルの内容ハッシュ(self) -> 内容ハッシュ {
        self.生成器の実行ファイルの内容ハッシュ
    }
}
