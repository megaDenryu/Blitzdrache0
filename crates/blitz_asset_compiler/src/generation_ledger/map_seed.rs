//! マップ生成の乱数の種。同じ種からは必ず同じ高さの並びが出る。
//!
//! 種を型で包むのは、同じu32でも格子の添字や個体数と混ぜてはならない量だからである。
//! 生成台帳の見出しがこの型を持つのは、種が変われば前に焼いたチャンクを1件も使えないためである。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct マップ生成の乱数の種(u32);

impl マップ生成の乱数の種 {
    pub fn 生成する(値: u32) -> Self {
        Self(値)
    }

    pub fn 値(self) -> u32 {
        self.0
    }
}

/// その世界が乱数の種から焼かれたものかどうか。種を持たない世界(手で書いた検証用の世界と、
/// ソースを材料に焼くだけのコンパイル工程)を「種0」のような値へ密輸しないために判別共用体で表す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 種の由来 {
    種から焼いた(マップ生成の乱数の種),
    種を持たない,
}
