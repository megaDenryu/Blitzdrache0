//! 生成台帳の検査。畳み方が公開されている既知の値と合うこと、テキストが往復して同じ中身に戻ること、
//! 見出しが食い違う台帳を空として扱うことを確かめる。

#![allow(clippy::unwrap_used)]

use std::collections::BTreeMap;

use super::content_hash::内容ハッシュ;
use super::generator_version::生成器の版;
use super::heading::生成台帳の見出し;
use super::map_seed::{マップ生成の乱数の種, 種の由来};
use super::text_format::{台帳のテキストを組み立てる, 台帳のテキストを解析する};

/// FNV-1a(64ビット)の公開されている値。空の入力は開始値そのもの、"a"と"foobar"は仕様書が挙げる例である。
#[test]
fn 既知の入力から公開されている値を出す() {
    assert_eq!(内容ハッシュ::バイト列から求める(b"").十六進の綴りを作る(), "cbf29ce484222325");
    assert_eq!(内容ハッシュ::バイト列から求める(b"a").十六進の綴りを作る(), "af63dc4c8601ec8c");
    assert_eq!(内容ハッシュ::バイト列から求める(b"foobar").十六進の綴りを作る(), "85944171f73967e8");
}

#[test]
fn 一バイト違えば別の値になる() {
    assert_ne!(内容ハッシュ::バイト列から求める(b"abc"), 内容ハッシュ::バイト列から求める(b"abd"));
}

#[test]
fn 十六進の綴りを往復する() {
    let ハッシュ = 内容ハッシュ::バイト列から求める(b"foobar");
    assert_eq!(内容ハッシュ::十六進の綴りから復元する(&ハッシュ.十六進の綴りを作る()), Some(ハッシュ));
    assert_eq!(内容ハッシュ::十六進の綴りから復元する("この綴りは十六進ではない"), None);
}

#[test]
fn 台帳のテキストが往復する() {
    let 見出し = 見本の見出しを作る(種の由来::種から焼いた(マップ生成の乱数の種::生成する(20260810)));
    let mut 記録 = BTreeMap::new();
    記録.insert((-1, 2), 内容ハッシュ::バイト列から求める("手前".as_bytes()));
    記録.insert((3, -4), 内容ハッシュ::バイト列から求める("隣".as_bytes()));
    let テキスト = 台帳のテキストを組み立てる(見出し, &記録);
    let 中身 = 台帳のテキストを解析する(&テキスト).unwrap();
    assert_eq!(中身.見出し, 見出し);
    assert_eq!(中身.チャンクごとの内容ハッシュ, 記録);
}

#[test]
fn 種を持たない見出しも往復する() {
    let 見出し = 見本の見出しを作る(種の由来::種を持たない);
    let テキスト = 台帳のテキストを組み立てる(見出し, &BTreeMap::new());
    assert_eq!(台帳のテキストを解析する(&テキスト).unwrap().見出し, 見出し);
}

#[test]
fn 形式宣言が違うテキストを拒む() {
    assert!(台帳のテキストを解析する("blitz_chunk_directory 1\nseed none\n").is_err());
}

fn 見本の見出しを作る(種の由来: 種の由来) -> 生成台帳の見出し {
    生成台帳の見出し::読み取った値から組み立てる(
        種の由来,
        生成器の版::生成する(7),
        内容ハッシュ::バイト列から求める("生成器の実行ファイル".as_bytes()),
        内容ハッシュ::バイト列から求める("焼き方の指定".as_bytes()),
    )
}

/// 焼き方の指定が見出しの一部であることを、見出しの等価で確かめる。台帳を読む工程は見出しが食い違えば記録を1件も使わないため、
/// この等価が破れていないことが「指定を変えた実行が前の指定の生成物を据え置かない」の根拠になる。
#[test]
fn 焼き方の指定が違えば見出しが食い違う() {
    let 別の焼き方の見出し = 生成台帳の見出し::読み取った値から組み立てる(
        種の由来::種を持たない,
        生成器の版::生成する(7),
        内容ハッシュ::バイト列から求める("生成器の実行ファイル".as_bytes()),
        内容ハッシュ::バイト列から求める("別の焼き方の指定".as_bytes()),
    );
    assert_ne!(見本の見出しを作る(種の由来::種を持たない), 別の焼き方の見出し);
}
