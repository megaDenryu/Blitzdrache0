//! 前回の台帳を読んだ結果。増分に使う台帳と、出力一式の全消去が必要かを一緒に運ぶ。

use super::ledger::生成台帳;

pub struct 生成台帳の読み込み結果 {
    台帳: 生成台帳,
    種または生成器の版が変わった: bool,
}

impl 生成台帳の読み込み結果 {
    pub(super) fn 生成する(台帳: 生成台帳, 種または生成器の版が変わった: bool) -> Self {
        Self {
            台帳,
            種または生成器の版が変わった,
        }
    }

    pub fn 種または生成器の版が変わったか(&self) -> bool {
        self.種または生成器の版が変わった
    }

    pub fn 台帳を受け取る(self) -> 生成台帳 {
        self.台帳
    }
}
