//! 生成の出力ルート: 生成物と生成台帳を置くディレクトリを表す型。台帳のファイル名の綴りと、台帳の読み書きを持つ。
//!
//! ディレクトリを裸のパスで運ばないのは、ソースの置き場と生成物の置き場が同じ`Path`では取り違えても型が通るためである。
//! 台帳のファイル名をこの型の中へ閉じるのは、綴りの写しが呼び出し側へ散ると、読む側と書く側で食い違ったときに
//! 「台帳が無い」という無言の全焼き直しになるためである。
//!
//! 役割ごとの置き場の型は、この型を包んで自分の綴りの規則を足す。パスの実体はこの型が1回だけ所有し、
//! 包む側は借用で貸し借りする。
//!
//! 注意: 台帳のファイルを読み書きするのはこの型だけである。生成台帳はパスもファイル操作も持たない。

use std::path::{Path, PathBuf};

mod cleanup;

use super::error::生成台帳エラー;
use super::ledger_text::生成台帳の本文;

/// 台帳のファイル名。出力ルートの直下に置く。綴りをこの型の中だけに置き、外へは`生成台帳を指すパスか`の判定で見せる。
/// 参照: `_doc/設計/大規模世界の生成と遠景.md`
const 生成台帳のファイル名: &str = "generation_ledger.txt";

#[repr(transparent)]
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 生成の出力ルート(PathBuf);

impl 生成の出力ルート {
    pub fn 生成する(ディレクトリ: PathBuf) -> Self {
        Self(ディレクトリ)
    }

    /// そのパスが生成台帳を指すか。生成の決定性の検収が突き合わせから台帳を除くために呼ぶ。
    /// 綴りでなく判定を見せるのは、台帳の名前を外の型が写しで持たないようにするためである。
    pub fn 生成台帳を指すパスか(パス: &Path) -> bool {
        パス.file_name().is_some_and(|名前| 名前 == 生成台帳のファイル名)
    }

    /// このディレクトリを作る。書き出す側だけが通り、読む側は通らない。
    pub fn ディレクトリを作る(&self) -> Result<(), 生成台帳エラー> {
        std::fs::create_dir_all(&self.0).map_err(|誤り| 生成台帳エラー::ディレクトリを作れなかった {
            パス: self.0.clone(),
            事由: 誤り.to_string(),
        })
    }

    /// この直下に置くファイルのパス。包む側の置き場の型が、自分の持つファイル名の綴りを渡して組む。
    /// クレートの外へ出さないのは、任意のファイル名を流せる汎用の口にしないためである。
    pub(crate) fn 直下のファイルのパス(&self, ファイル名: &str) -> PathBuf {
        self.0.join(ファイル名)
    }

    /// 相対パスとして与えられたファイルのパス。綴りへ写し替えずに組む。
    pub(crate) fn 直下の相対パスが指すファイル(&self, 相対パス: &std::path::Path) -> PathBuf {
        self.0.join(相対パス)
    }

    pub fn 表示の綴り(&self) -> std::path::Display<'_> {
        self.0.display()
    }

    pub(crate) fn ファイル走査へ貸すディレクトリ(&self) -> &Path {
        &self.0
    }

    /// 別のプロセスの引数として渡すためのディレクトリ。
    ///
    /// 注意: この型が生のパスへ戻る唯一の口である。プロセスの引数は綴りでしか渡せないため、型で運べるのは
    /// この呼び出しの手前までである。ファイルを組み立てる用途でこれを呼んではならない(綴りの規則がこの型の外へ散る)。
    pub fn プロセスの引数へ渡すディレクトリ(&self) -> &Path {
        &self.0
    }

    /// 台帳が無いときと読めないときは値なしを返す。どちらも記録を1件も使えない点で同じであり、
    /// 呼び出し側は空の台帳として扱って全部を焼き直す。
    pub(super) fn 台帳の本文を読む(&self) -> Option<生成台帳の本文> {
        std::fs::read_to_string(self.直下のファイルのパス(生成台帳のファイル名))
            .ok()
            .map(生成台帳の本文::読み取った綴りから作る)
    }

    pub(super) fn 台帳の本文を書く(&self, 本文: &生成台帳の本文) -> Result<(), 生成台帳エラー> {
        let パス = self.直下のファイルのパス(生成台帳のファイル名);
        std::fs::write(&パス, 本文.綴り()).map_err(|誤り| 生成台帳エラー::ファイルの書き出しに失敗した {
            パス,
            事由: 誤り.to_string(),
        })
    }
}
