//! 焼き直しの勘定: 1回の生成で何本のチャンクを焼き直し、何本を据え置いたかの数え上げと、その報告の行の組み立て。
//!
//! 増分が効いていることは生成物の中身を見ても分からない。焼き直した本数が0本であることが唯一の証拠であるため、
//! 数え上げと報告の綴りを型として持つ。
//! 注意: 報告の行の綴りは`xtask/src/generation_tally.rs`が読み取る側として同じものを持つ。
//! 食い違えば検収が本数を読めずに失敗する。

use super::ledger::チャンクの焼き直し判定;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 焼き直しの勘定 {
    焼き直した本数: usize,
    据え置いた本数: usize,
}

impl 焼き直しの勘定 {
    pub fn 判定の一覧から数える(判定一覧: impl Iterator<Item = チャンクの焼き直し判定>) -> Self {
        let mut 勘定 = Self::default();
        for 判定 in 判定一覧 {
            match 判定 {
                チャンクの焼き直し判定::据え置く { .. } => 勘定.据え置いた本数 += 1,
                チャンクの焼き直し判定::焼き直す => 勘定.焼き直した本数 += 1,
            }
        }
        勘定
    }

    pub fn 焼き直した本数(self) -> usize {
        self.焼き直した本数
    }

    pub fn 報告の行を作る(self) -> String {
        format!(
            "焼き直したチャンク数={} 据え置いたチャンク数={}",
            self.焼き直した本数, self.据え置いた本数
        )
    }
}
