//! テキスト1枚を台帳の中身へ解析する工程。受け取るのは読み込んだテキスト、返すのは見出しとチャンクごとの内容ハッシュである。
//!
//! 未知の版と欄の綴り違いを型付きエラーで拒むのは、別形式のテキストを台帳として読み進めると、
//! 焼き直すべきチャンクを据え置いて古い生成物を残すためである。

mod chunk_line;

use super::super::content_hash::内容ハッシュ;
use super::super::error::生成台帳エラー;
use super::super::generator_version::生成器の版;
use super::super::heading::生成台帳の見出し;
use super::super::map_seed::{マップ生成の乱数の種, 種の由来};
use super::{
    台帳のテキストが表す中身, 対応版, 形式名, 焼き方の指定の欄, 生成器の実行ファイルの欄, 生成器の版の欄, 種の欄, 種を持たないときの綴り
};

pub(in crate::generation_ledger) fn 台帳のテキストを解析する(
    テキスト: &str,
) -> Result<台帳のテキストが表す中身, 生成台帳エラー> {
    let 行一覧: Vec<&str> = テキスト.lines().collect();
    let [宣言行, 種の行, 版の行, 実行ファイルの行, 焼き方の行, チャンクの行一覧 @ ..] = 行一覧.as_slice() else {
        return Err(生成台帳エラー::形式宣言が違う(
            テキスト.lines().next().unwrap_or_default().to_string(),
        ));
    };
    形式宣言を検査する(宣言行)?;
    let 種の由来 = 種の由来を読む(欄の値を読む(種の行, 種の欄, 2)?)?;
    let 生成器の版 = 生成器の版::十進の綴りから復元する(欄の値を読む(版の行, 生成器の版の欄, 3)?)?;
    let 実行ファイルの内容ハッシュ = 十六進の欄を読む(実行ファイルの行, 生成器の実行ファイルの欄, 4)?;
    let 焼き方の指定の内容ハッシュ = 十六進の欄を読む(焼き方の行, 焼き方の指定の欄, 5)?;
    Ok(台帳のテキストが表す中身 {
        見出し: 生成台帳の見出し::読み取った値から組み立てる(
            種の由来,
            生成器の版,
            実行ファイルの内容ハッシュ,
            焼き方の指定の内容ハッシュ,
        ),
        チャンクごとの内容ハッシュ: chunk_line::チャンクの行一覧を読む(チャンクの行一覧)?,
    })
}

fn 十六進の欄を読む(行: &str, 欄名: &str, 行番号: usize) -> Result<内容ハッシュ, 生成台帳エラー> {
    let 綴り = 欄の値を読む(行, 欄名, 行番号)?;
    内容ハッシュ::十六進の綴りから復元する(綴り).ok_or_else(|| 生成台帳エラー::行を読めない {
        行番号,
        内容: 行.to_string(),
    })
}

fn 形式宣言を検査する(宣言行: &str) -> Result<(), 生成台帳エラー> {
    let 欄一覧: Vec<&str> = 宣言行.split_whitespace().collect();
    let [名前, 版] = 欄一覧.as_slice() else {
        return Err(生成台帳エラー::形式宣言が違う(宣言行.to_string()));
    };
    if *名前 != 形式名 {
        return Err(生成台帳エラー::形式宣言が違う(宣言行.to_string()));
    }
    if *版 != 対応版 {
        return Err(生成台帳エラー::未対応の版である((*版).to_string()));
    }
    Ok(())
}

fn 欄の値を読む<'行>(行: &'行 str, 欄名: &str, 行番号: usize) -> Result<&'行 str, 生成台帳エラー> {
    let 欄一覧: Vec<&str> = 行.split_whitespace().collect();
    match 欄一覧.as_slice() {
        [名前, 値] if *名前 == 欄名 => Ok(値),
        _ => Err(生成台帳エラー::行を読めない {
            行番号,
            内容: 行.to_string(),
        }),
    }
}

fn 種の由来を読む(値: &str) -> Result<種の由来, 生成台帳エラー> {
    if 値 == 種を持たないときの綴り {
        return Ok(種の由来::種を持たない);
    }
    値.parse::<u32>()
        .map(|数| 種の由来::種から焼いた(マップ生成の乱数の種::生成する(数)))
        .map_err(|_| 生成台帳エラー::行を読めない {
            行番号: 2,
            内容: 値.to_string(),
        })
}
