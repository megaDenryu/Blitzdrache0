//! 内容ハッシュ: バイト列やファイルの中身を64ビットの1つの値へ畳んだもの。生成台帳が「前に焼いたときと中身が同じか」を
//! 全バイトを覚えずに答えるために置く。
//!
//! 畳み方はFNV-1a(64ビット)である。公開されている開始値と掛ける値の2つだけで定まるため外部の依存を1つも足さずに書け、
//! 既知の値で実装そのものを検査できる。暗号の用途ではないため、意図して衝突を作られることへの強さは要求しない。
//! 使うのは、同じ中身が必ず同じ値になることと、違う中身が同じ値になる確率が実用上無視できることの2つだけである。

use std::io::Read;
use std::path::Path;

use super::error::生成台帳エラー;

const 畳み込みの開始値: u64 = 0xcbf2_9ce4_8422_2325;
const 畳み込みに掛ける値: u64 = 0x0000_0100_0000_01b3;

/// ファイルを1回に読み進める大きさ。中身を丸ごとメモリへ載せないために区切って読む。
const 読み取りの一区切りのバイト数: usize = 1 << 20;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 内容ハッシュ(u64);

impl 内容ハッシュ {
    pub fn バイト列から求める(バイト列: &[u8]) -> Self {
        Self(畳み込む(畳み込みの開始値, バイト列.iter().copied()))
    }

    /// ファイルの中身を先頭から一区切りずつ読んで畳む。読んだ区切りは次の区切りで捨てるため、
    /// 保持するメモリはファイルの大きさに依らず一定である。
    pub fn ファイルの中身から求める(パス: &Path) -> Result<Self, 生成台帳エラー> {
        let mut ファイル = std::fs::File::open(パス).map_err(|誤り| 読み取り失敗(パス, &誤り))?;
        let mut 区切り = vec![0_u8; 読み取りの一区切りのバイト数];
        let mut 畳んだ値 = 畳み込みの開始値;
        loop {
            let 読み取ったバイト数 = ファイル.read(&mut 区切り).map_err(|誤り| 読み取り失敗(パス, &誤り))?;
            if 読み取ったバイト数 == 0 {
                return Ok(Self(畳んだ値));
            }
            畳んだ値 = 畳み込む(畳んだ値, 区切り.iter().copied().take(読み取ったバイト数));
        }
    }

    /// ファイルがまだ無いときは値なしを返す。「無い」と「中身がたまたまこの値」を取り違えないために、
    /// 特別な数値でなく値なしで表す。
    pub fn ファイルがあれば中身から求める(パス: &Path) -> Result<Option<Self>, 生成台帳エラー> {
        if !パス.is_file() {
            return Ok(None);
        }
        Self::ファイルの中身から求める(パス).map(Some)
    }

    /// 台帳のテキストへ書くときの綴り。桁を16に固定するのは、行の見た目が値によって揺れないためである。
    pub fn 十六進の綴りを作る(self) -> String {
        format!("{:016x}", self.0)
    }

    pub fn 十六進の綴りから復元する(綴り: &str) -> Option<Self> {
        u64::from_str_radix(綴り, 16).ok().map(Self)
    }
}

fn 畳み込む(開始値: u64, バイト列: impl Iterator<Item = u8>) -> u64 {
    let mut 畳んだ値 = 開始値;
    for バイト in バイト列 {
        畳んだ値 ^= u64::from(バイト);
        畳んだ値 = 畳んだ値.wrapping_mul(畳み込みに掛ける値);
    }
    畳んだ値
}

fn 読み取り失敗(パス: &Path, 誤り: &std::io::Error) -> 生成台帳エラー {
    生成台帳エラー::ファイルの読み取りに失敗した {
        パス: パス.to_path_buf(),
        事由: 誤り.to_string(),
    }
}
