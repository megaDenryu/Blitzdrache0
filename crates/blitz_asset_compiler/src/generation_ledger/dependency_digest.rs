//! ソース依存の一式を1つの内容ハッシュへ畳む工程。受け取るのはコンパイルが読んだソースのパスの並び、
//! 返すのはその一式を代表する内容ハッシュである。
//!
//! 材料が1つとは限らないため、実行時形式のコンパイルはこの畳んだ値を増分の鍵に使う。たとえば地面のチャンクは
//! 高さ格子のほかに同居させる植生の原型を読む。高さ格子だけを鍵にすると、原型を差し替えた実行が古いチャンクを据え置く。
//! パスの綴りも畳むのは、依存の並びや名前が変わったことも中身の変化と同じく焼き直しの理由になるためである。

use std::path::{Path, PathBuf};

use super::content_hash::内容ハッシュ;
use super::error::生成台帳エラー;

pub fn ソース依存一式の内容ハッシュを求める(
    ソース依存一覧: &[PathBuf]
) -> Result<内容ハッシュ, 生成台帳エラー> {
    let mut 一覧の綴り = String::new();
    for パス in ソース依存一覧 {
        let 中身のハッシュ = 内容ハッシュ::ファイルがあれば中身から求める(パス)?;
        一覧の綴り.push_str(&一件の綴りを作る(パス, 中身のハッシュ));
    }
    Ok(内容ハッシュ::バイト列から求める(一覧の綴り.as_bytes()))
}

/// 依存1件の綴り。ソースが消えている場合を空の綴りでなく「無い」と書くのは、
/// 中身のハッシュがたまたま空の綴りになる場合と取り違えないためである。
fn 一件の綴りを作る(パス: &Path, 中身のハッシュ: Option<内容ハッシュ>) -> String {
    let パスの綴り = 区切りを揃えたパスの綴りを作る(パス);
    match 中身のハッシュ {
        Some(ハッシュ) => format!("{パスの綴り} {}\n", ハッシュ.十六進の綴りを作る()),
        None => format!("{パスの綴り} 無い\n"),
    }
}

/// 注意: パスの区切りを斜線へ揃える。実行時カタログが依存一覧を書き出すときに同じ揃え方をするため、
/// 揃えずに畳むとカタログを往復した前後で鍵が食い違い、Windowsでは毎回すべてのチャンクが焼き直しになる。
fn 区切りを揃えたパスの綴りを作る(パス: &Path) -> String {
    パス.display().to_string().replace('\\', "/")
}
