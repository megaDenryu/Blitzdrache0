//! 今回の宣言とソース依存の一式を1つの内容ハッシュへ畳む工程。受け取るのは今回のカタログがその対象へ対応付けたソースと、
//! コンパイルが読んだソースのパスの並び、返すのはその一式を代表する内容ハッシュである。
//!
//! 依存一式だけでなく今回の宣言も畳むのは、依存一式が前回の焼き上がりの記録だからである。宣言を畳まないと、
//! 別のソースルートを指した実行や、同じ安定IDの参照先を別のパスへ付け替えた実行が、前回の依存が残っている限り
//! 「中身が同じ」と判定されて据え置かれ、新しい宣言が無視される。
//!
//! 材料が1つとは限らないため依存一式も畳む。たとえば地面のチャンクは高さ格子のほかに同居させる植生の原型を読む。
//! 高さ格子だけを鍵にすると、原型を差し替えた実行が古いチャンクを据え置く。
//! パスの綴りも畳むのは、依存の並びや名前が変わったことも中身の変化と同じく焼き直しの理由になるためである。

use std::path::{Path, PathBuf};

use super::content_hash::内容ハッシュ;
use super::error::生成台帳エラー;

pub fn 今回の宣言と依存一式の内容ハッシュを求める(
    宣言が指すソース: &Path,
    ソース依存一覧: &[PathBuf],
) -> Result<内容ハッシュ, 生成台帳エラー> {
    let mut 一覧の綴り = 一件の綴りを作る("宣言", 宣言が指すソース)?;
    for パス in ソース依存一覧 {
        一覧の綴り.push_str(&一件の綴りを作る("依存", パス)?);
    }
    Ok(内容ハッシュ::バイト列から求める(一覧の綴り.as_bytes()))
}

/// 1件の綴り。ソースが消えている場合を空の綴りでなく「無い」と書くのは、中身のハッシュがたまたま空の綴りになる場合と
/// 取り違えないためである。宣言と依存を頭の語で分けるのは、同じパスが両方に現れても位置の違いが綴りに残るようにするためである。
fn 一件の綴りを作る(頭の語: &str, パス: &Path) -> Result<String, 生成台帳エラー> {
    let パスの綴り = 区切りを揃えたパスの綴りを作る(パス);
    Ok(match 内容ハッシュ::ファイルがあれば中身から求める(パス)? {
        Some(ハッシュ) => format!("{頭の語} {パスの綴り} {}\n", ハッシュ.十六進の綴りを作る()),
        None => format!("{頭の語} {パスの綴り} 無い\n"),
    })
}

/// 注意: パスの区切りを斜線へ揃える。実行時カタログが依存一覧を書き出すときに同じ揃え方をするため、
/// 揃えずに畳むとカタログを往復した前後で鍵が食い違い、Windowsでは毎回すべてのチャンクが焼き直しになる。
fn 区切りを揃えたパスの綴りを作る(パス: &Path) -> String {
    パス.display().to_string().replace('\\', "/")
}
