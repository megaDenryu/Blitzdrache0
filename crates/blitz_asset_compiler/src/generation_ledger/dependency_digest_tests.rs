//! 増分の鍵の反証。前回の依存一式をそのまま渡しても、今回の宣言が指すソースが変われば鍵が変わることを2つの場合で確かめる。
//! 1つはソースルートを切り替えた場合、もう1つは同じ安定IDの参照先を別のパスへ付け替えた場合である。
//! どちらも「前回の依存ファイルが残っていれば据え置かれる」という誤りの再発を止めるために置く。

#![allow(clippy::unwrap_used)]

use std::path::{Path, PathBuf};

use super::dependency_digest::今回の宣言と依存一式の内容ハッシュを求める;

const 同じ中身: &[u8] = b"height grid bytes";

/// 検査ごとに専用のディレクトリを作り直す。同時に走る他の検査とファイルを取り合わないためである。
fn 作り直した検査用ディレクトリ(検査名: &str) -> PathBuf {
    let ディレクトリ = std::env::temp_dir().join("blitz_generation_ledger_digest").join(検査名);
    let _ = std::fs::remove_dir_all(&ディレクトリ);
    std::fs::create_dir_all(&ディレクトリ).unwrap();
    ディレクトリ
}

fn ファイルを置く(パス: &Path, 中身: &[u8]) {
    if let Some(親) = パス.parent() {
        std::fs::create_dir_all(親).unwrap();
    }
    std::fs::write(パス, 中身).unwrap();
}

/// ソースルートを切り替えた実行は焼き直す。前回の依存一覧は古いルートのファイルを指したままであり、
/// そのファイルが残っていて中身も同じでも、今回の宣言が別のルートを指す以上は据え置いてはならない。
#[test]
fn ソースルートを切り替えたら鍵が変わる() {
    let 検査用 = 作り直した検査用ディレクトリ("source_root_switch");
    let 古いルートのソース = 検査用.join("a").join("chunk.heightgrid");
    let 新しいルートのソース = 検査用.join("b").join("chunk.heightgrid");
    ファイルを置く(&古いルートのソース, 同じ中身);
    ファイルを置く(&新しいルートのソース, 同じ中身);

    let 前回の依存一覧 = vec![古いルートのソース.clone()];
    let 前回の鍵 = 今回の宣言と依存一式の内容ハッシュを求める(&古いルートのソース, &前回の依存一覧).unwrap();
    let 今回の鍵 = 今回の宣言と依存一式の内容ハッシュを求める(&新しいルートのソース, &前回の依存一覧).unwrap();
    assert_ne!(前回の鍵, 今回の鍵);
}

/// 同じ安定IDの参照先を別のパスへ付け替えた実行は焼き直す。中身が同じでも、次に焼く材料は別のファイルである。
#[test]
fn 同じ安定idの参照先を付け替えたら鍵が変わる() {
    let 検査用 = 作り直した検査用ディレクトリ("declaration_repoint");
    let 元の参照先 = 検査用.join("chunk.heightgrid");
    let 付け替えた参照先 = 検査用.join("chunk_renamed.heightgrid");
    ファイルを置く(&元の参照先, 同じ中身);
    ファイルを置く(&付け替えた参照先, 同じ中身);

    let 前回の依存一覧 = vec![元の参照先.clone()];
    let 前回の鍵 = 今回の宣言と依存一式の内容ハッシュを求める(&元の参照先, &前回の依存一覧).unwrap();
    let 今回の鍵 = 今回の宣言と依存一式の内容ハッシュを求める(&付け替えた参照先, &前回の依存一覧).unwrap();
    assert_ne!(前回の鍵, 今回の鍵);
}

/// 宣言も依存も動いていなければ鍵は同じである。これが成り立たないと据え置きが一度も起きず、増分そのものが無意味になる。
#[test]
fn 宣言も依存も動かなければ鍵は同じ() {
    let 検査用 = 作り直した検査用ディレクトリ("no_change");
    let ソース = 検査用.join("chunk.heightgrid");
    ファイルを置く(&ソース, 同じ中身);

    let 依存一覧 = vec![ソース.clone()];
    let 一度目 = 今回の宣言と依存一式の内容ハッシュを求める(&ソース, &依存一覧).unwrap();
    let 二度目 = 今回の宣言と依存一式の内容ハッシュを求める(&ソース, &依存一覧).unwrap();
    assert_eq!(一度目, 二度目);
}

/// 宣言に現れない材料(同居させる植生の原型など)の中身が変われば鍵が変わる。
#[test]
fn 宣言以外の依存の中身が変われば鍵が変わる() {
    let 検査用 = 作り直した検査用ディレクトリ("dependency_content_change");
    let 宣言のソース = 検査用.join("chunk.heightgrid");
    let 原型 = 検査用.join("prototype.gltf");
    ファイルを置く(&宣言のソース, 同じ中身);
    ファイルを置く(&原型, b"prototype");
    let 依存一覧 = vec![宣言のソース.clone(), 原型.clone()];
    let 変える前 = 今回の宣言と依存一式の内容ハッシュを求める(&宣言のソース, &依存一覧).unwrap();
    ファイルを置く(&原型, b"prototype changed");
    let 変えた後 = 今回の宣言と依存一式の内容ハッシュを求める(&宣言のソース, &依存一覧).unwrap();
    assert_ne!(変える前, 変えた後);
}
