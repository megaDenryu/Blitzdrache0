//! 部品で建てた家並みの世界を焼く工程。1つの組み立て規則を軒ごとに種を変えて展開し、
//! 部品の種類ごとに1つのインスタンス群へまとめて焼く。
//!
//! **この世界が実証するのは、描画発行数が軒数に比例しないことである。** 描画対象になるのは部品の種類であり、
//! 軒数で伸びるのは1つの群の中の配置列だけである。地面の焼き方と群の組み立て方と混合関数は
//! 地形・植生・部品の展開の工程をそのまま呼ぶ。写しを持つと、同じ宣言から別の配置が出る。
//!
//! 見本の集落と分けるのは、置くものの決め方が正反対だからである。あちらは配置様式が地面の上へ直に個体を散らす。
//! こちらは接合点だけから組み上がった1軒ぶんの配置表を、軒数ぶん集めて部品ごとに畳む。
//! 参照: `_doc/設計/部品カタログと接合点.md`「設計の核心」

mod error;
