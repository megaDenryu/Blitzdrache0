use blitz_engine::{アセットID, チャンク座標};

use crate::compile::コンパイル済みシーン;
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子を読み込む;
use crate::scene_compiler::ソースアセットのコンパイル係;

pub use error::部品の家並みのコンパイルエラー;
pub use house_count::家並みの軒数;
pub use specification::家並みの指定;

impl ソースアセットのコンパイル係<'_> {
    pub fn 部品で建てた家並みチャンクをコンパイルする(
        &self,
        id: &アセットID,
        所有チャンク: チャンク座標,
        指定: &家並みの指定,
    ) -> Result<コンパイル済みシーン, アセットコンパイルエラー> {
        let パス = self.安定idが指すソースのパスを参照する(id)?;
        let 格子 = 高さ格子を読み込む(パス)?;
        let 組み立て = self.部品で建てた家並みのシーンを組み立てる(&格子, 所有チャンク, パス.to_path_buf(), 指定)?;
        コンパイル済みシーン::組み立てたシーンから焼く(組み立て)
    }
}
