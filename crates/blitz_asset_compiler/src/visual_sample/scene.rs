//! 目視見本のシーンを組み立てる工程。受け取るのはカタログと高さ格子と所有チャンクと据えるものの指定、
//! 返すのは庭の地面1つと固定物2つと群を種の数だけ持つシーンデータである。
//!
//! 地面を地形LODメッシュ群として焼くのは、地形の世界と同じ経路で焼くことで、小物の接地が描画される面と同じ求め方の上に乗るためである。
//! 地面の上へ何をどの位置で据えるかは`fixed_objects`が持ち、小物1種の群の組み立ては見本の集落の工程をそのまま呼ぶ。

use std::path::PathBuf;

use blitz_engine::{
    カタログ, シーンデータ, チャンク座標, マテリアルデータ, 描画対象ID, 描画対象データ, 描画形状, 材質集合, 金属粗さPBRデータ
};

use super::fixed_objects;
use super::目視見本の指定;
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子;
use crate::terrain::lod_bake;
use crate::texture_storage::テクスチャ格納方針;
use crate::vegetation::group_object;
use crate::village::prop_group::小物群の描画対象を作る;

/// 庭の地面の描画対象番号。1つの高さ格子が1つの描画対象になるため常にこの値であり、固定物と群はこの次から番号を取る。
const 庭の地面の描画対象番号: u64 = 0;

pub(super) fn 組み立てる(
    カタログ: &カタログ,
    格子: &高さ格子,
    所有チャンク: チャンク座標,
    ソースパス: PathBuf,
    指定: &目視見本の指定,
    方針: テクスチャ格納方針,
) -> Result<シーンデータ, アセットコンパイルエラー> {
    let 庭の地面 = 描画対象データ::生成する(
        描画対象ID::生成する(庭の地面の描画対象番号),
        所有チャンク,
        group_object::恒等変換を作る(),
        描画形状::地形LODメッシュ群(lod_bake::段別メッシュを焼く(格子)?),
        材質集合::単一材質から生成する(庭の地面のマテリアルを作る()),
    );
    let (mut 残りの描画対象, 固定物の参照一覧) = fixed_objects::据える(カタログ, 格子, 所有チャンク, 指定, 方針)?;
    let mut 参照ファイル一覧 = vec![ソースパス];
    参照ファイル一覧.extend(固定物の参照一覧);
    let mut 通し番号 = fixed_objects::最後の描画対象番号;
    for 群の指定 in &指定.群一覧 {
        通し番号 += 1;
        let (対象, 参照一覧) = 小物群の描画対象を作る(カタログ, 格子, 所有チャンク, 通し番号, 群の指定, 方針)?;
        参照ファイル一覧.extend(参照一覧);
        残りの描画対象.push(対象);
    }
    Ok(シーンデータ::生成する(
        庭の地面,
        残りの描画対象,
        参照ファイル一覧,
        None,
        Vec::new(),
    ))
}

/// 庭の地面は乾いた土に草が混じった色の非金属として描く。地形の世界が白いのは植生の緑と画素で見分けるためであり、
/// この世界は絵として見るため、実測のアルベドに近い暗さを選ぶ。白いままでは昼に地面が飽和し、
/// 球へ映り込む地面が空より明るくなって、間接照明の絵が現実のどこにも無いものになる。
///
/// 注意: この係数は遠景地面のベースカラーと違う値でなければならない。検収の領域マスクは1色の一致で庭の地面を選ぶため、
/// 同じ値にすると遠景地面まで庭の地面として数えられ、破綻防止帯の割合が庭の性質を表さなくなる。
fn 庭の地面のマテリアルを作る() -> マテリアルデータ {
    マテリアルデータ::金属粗さPBR(金属粗さPBRデータ {
        ベースカラー: None,
        金属粗さ: None,
        法線マップ: None,
        ベースカラー係数: [0.14, 0.16, 0.10, 1.0],
        金属度係数: 0.0,
        粗さ係数: 0.95,
    })
}
