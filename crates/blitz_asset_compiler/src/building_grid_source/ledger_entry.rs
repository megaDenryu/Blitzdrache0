//! 台帳に載る建物1件。格子のソースと、それを解いて検査を通した定義を1つの組で持つ。
//!
//! 2つを組で持つのは、カタログの組み立てが定義を読み、ソースアセットの書き出しが同じ1件のソースを読むためである。
//! 書き出しがソースをディスクから読み直す形にすると、台帳を写し取った後に保存が走ったとき、カタログと格子の世代が
//! 揃わないまま1つのチャンクへ焼かれる。組で持てば、台帳を写し取った時点で両方の世代が揃う。

use super::error::建物の格子のソースエラー;
use super::grid_definition::格子由来の建物定義;
use super::source::建物の格子ソース;
use crate::runtime_compilation::建物定義ID;

#[derive(Debug, Clone, PartialEq)]
pub struct 台帳に載る建物 {
    格子ソース: 建物の格子ソース,
    解けた定義: 格子由来の建物定義,
}

impl 台帳に載る建物 {
    /// ソースを解いて組にする。升目の宣言の破れと到達の破れはここで型付きエラーになり、
    /// 解けた組だけが台帳へ入る。
    pub fn ソースを解いて生成する(格子ソース: 建物の格子ソース) -> Result<Self, 建物の格子のソースエラー> {
        let 解けた定義 = 格子ソース.格子由来の建物定義へ解く()?;
        Ok(Self {
            格子ソース, 解けた定義
        })
    }

    pub fn 識別子(&self) -> &建物定義ID {
        self.解けた定義.識別子()
    }

    pub fn 格子ソース(&self) -> &建物の格子ソース {
        &self.格子ソース
    }

    pub fn 解けた定義(&self) -> &格子由来の建物定義 {
        &self.解けた定義
    }
}
