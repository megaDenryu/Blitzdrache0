//! 建物の格子の置き場: プロジェクトの編集データの中で建物の格子が並ぶディレクトリという役割を持つパス。
//!
//! 建物1件ごとにディレクトリを掘り、その名前を建物定義IDにする。名前をそのまま識別子に使うのは、
//! 置き場を数え上げるだけで台帳の見出しが揃うためであり、ファイルの中の名乗りと突き合わせて食い違いを拒む。
//!
//! パスの綴りをこの型のメソッドへ閉じるのは、編集サーバーとカタログの生成入口の両方が同じ置き場を開くためである。
//! 綴りを呼び出し側へ散らすと、書く側と読む側が別のディレクトリを見ていても双方とも動いてしまう。
//! 参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断2」

use std::path::{Path, PathBuf};

use super::error::建物の格子のソースエラー;
use super::grid_file::建物の格子のファイル;
use crate::runtime_compilation::建物定義ID;

const 編集データディレクトリ名: &str = "editor_data";
const 建物ディレクトリ名: &str = "建物";
const 格子ファイル名: &str = "格子.json";

#[derive(Debug, Clone)]
pub struct 建物の格子の置き場 {
    パス: PathBuf,
}

impl 建物の格子の置き場 {
    pub fn プロジェクトルートから生成する(プロジェクトルート: &Path) -> Self {
        Self {
            パス: プロジェクトルート.join(編集データディレクトリ名).join(建物ディレクトリ名),
        }
    }

    pub fn パス(&self) -> &Path {
        &self.パス
    }

    pub fn 建物定義の格子ファイル(&self, 識別子: &建物定義ID) -> 建物の格子のファイル {
        建物の格子のファイル::生成する(self.パス.join(識別子.綴り()).join(格子ファイル名))
    }

    /// 置き場に格子ファイルを持つ建物定義IDを昇順に並べる。置き場そのものが無いときは0件である
    /// (建物をまだ1件も作っていないプロジェクトが正当に成立する)。
    pub fn 保存されている建物定義の識別子を昇順に数え上げる(
        &self,
    ) -> Result<Vec<建物定義ID>, 建物の格子のソースエラー> {
        if !self.パス.is_dir() {
            return Ok(Vec::new());
        }
        let 読み取り = std::fs::read_dir(&self.パス).map_err(|原因| self.置き場を読めないエラーを作る(原因))?;
        let mut 一覧 = Vec::new();
        for 項目結果 in 読み取り {
            let 項目 = 項目結果.map_err(|原因| self.置き場を読めないエラーを作る(原因))?;
            let ディレクトリ名 = 項目.file_name().to_string_lossy().to_string();
            let Ok(識別子) = 建物定義ID::生成する(ディレクトリ名) else {
                continue;
            };
            if self.建物定義の格子ファイル(&識別子).パス().is_file() {
                一覧.push(識別子);
            }
        }
        一覧.sort_by(|左, 右| 左.綴り().cmp(右.綴り()));
        Ok(一覧)
    }

    fn 置き場を読めないエラーを作る(&self, 原因: std::io::Error) -> 建物の格子のソースエラー {
        建物の格子のソースエラー::置き場を読めない {
            置き場: self.パス.display().to_string(),
            原因,
        }
    }
}
