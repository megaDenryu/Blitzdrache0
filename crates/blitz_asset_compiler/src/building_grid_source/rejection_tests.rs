//! 変換できない宣言が保存の検査で拒まれることの反証。到達不能・継いだ面へ壁・浮いた階・升目が空の4件を見る。
//!
//! 件数でなくどの前提が破れたかを枝で確かめるのは、検査が偶然別の理由で落ちているのを合格と読み違えないためである。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_assembly::ベイ格子エラー;

use super::error::建物の格子のソースエラー;
use super::source_fixture::{
    原点の座標, 四面へ壁を入れた升目, 平壁を入れる, 座標を作る, 道具が作る初期の格子, 骨格だけの升目
};

fn 升目の破れを取り出す(
    結果: Result<super::grid_definition::格子由来の建物定義, 建物の格子のソースエラー>
) -> ベイ格子エラー {
    match 結果 {
        Err(建物の格子のソースエラー::升目が成り立たない { 原因, .. }) => 原因,
        Err(他) => panic!("升目の破れとして拒むはずが別の理由で落ちた: {他}"),
        Ok(_) => panic!("拒むはずの格子が受理された"),
    }
}

#[test]
fn 升目を1つも持たない格子は拒まれる() {
    let mut ソース = 道具が作る初期の格子("grid_empty");
    ソース.格子.升目一覧.clear();
    assert_eq!(升目の破れを取り出す(ソース.格子由来の建物定義へ解く()), ベイ格子エラー::升目が1つも無い);
}

#[test]
fn 根から到達できない升目を持つ格子は拒まれる() {
    let mut ソース = 道具が作る初期の格子("grid_unreachable");
    ソース.格子.升目一覧.push(四面へ壁を入れた升目(座標を作る(4, 0, 0)));
    assert!(matches!(
        升目の破れを取り出す(ソース.格子由来の建物定義へ解く()),
        ベイ格子エラー::根から到達できない升目がある { .. }
    ));
}

#[test]
fn 隣を継ぐ面へ壁を入れた格子は拒まれる() {
    let mut ソース = 道具が作る初期の格子("grid_joined_wall");
    ソース.格子.升目一覧 = vec![四面へ壁を入れた升目(原点の座標()), 骨格だけの升目(座標を作る(1, 0, 0))];
    assert!(matches!(
        升目の破れを取り出す(ソース.格子由来の建物定義へ解く()),
        ベイ格子エラー::隣の升目がある側面へ壁を入れている { .. }
    ));
}

#[test]
fn 真下に升目の無い階を持つ格子は拒まれる() {
    let mut ソース = 道具が作る初期の格子("grid_floating_floor");
    ソース.格子.升目一覧.push(四面へ壁を入れた升目(座標を作る(0, 0, 2)));
    assert!(matches!(
        升目の破れを取り出す(ソース.格子由来の建物定義へ解く()),
        ベイ格子エラー::真下に升目が無い { .. }
    ));
}

#[test]
fn 屋根の下に升目を積んだ格子は拒まれる() {
    let mut ソース = 道具が作る初期の格子("grid_roof_under_floor");
    let mut 上の階 = 四面へ壁を入れた升目(座標を作る(0, 0, 1));
    上の階.右面 = 平壁を入れる();
    ソース.格子.升目一覧.push(上の階);
    assert!(matches!(
        升目の破れを取り出す(ソース.格子由来の建物定義へ解く()),
        ベイ格子エラー::真上に升目がある升目へ屋根を載せている { .. }
    ));
}
