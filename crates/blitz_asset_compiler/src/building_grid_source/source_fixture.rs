//! 建物の格子のソースの試験の材料。道具が新しい建物を作ったときの初期の格子と、そこから欄を1つだけ
//! 崩した格子を組む口を持つ。
//!
//! 初期の格子は3箇所に同じ形を手書きしている。ブラウザの生成
//! (`editor_web/src/ツール/建物編集/編集モデル/初期の建物の格子を作る.ts`)、ここ(受入の検査の材料)、
//! HTTPの往復の材料(`crates/editor_server/tests/integration/common/building_grid_fixture.rs`)である。言語と境界が
//! 違うため綴りを1つに束ねられず、一致は目視と、ここの試験(道具が作る初期の格子が保存の検査を通ること)で保つ。
//! 3箇所がずれると、道具が作った直後の建物が保存で拒まれる形の食い違いが起こる。
//! 参照: `~/.claude/skills/エディター制作`「生成と検証の対称性」

#![cfg(test)]

use crate::runtime_compilation::建物定義ID;

use super::cell_source::{升目の屋根ソース, 升目の床ソース, 升目の座標ソース, 升目ソース};
use super::opening_source::{はめ口ソース, 壁の外面の飾りソース, 壁の種類ソース};
use super::source::{
    升目の複体ソース, 建物の入口方向ソース, 建物の格子ソース, 建物の格子ソースの現在の形式版, 建物の装飾ソース
};

/// 道具が新しい建物を1件作った直後の格子。1升目に骨格を1件据え、4面すべてへ壁を入れ、床を張り屋根を載せる。
/// **この形が保存の検査を必ず通ることを、生成と受入の一致の試験が確かめる。**
pub(crate) fn 道具が作る初期の格子(識別子の綴り: &str) -> 建物の格子ソース {
    建物の格子ソース {
        形式版: 建物の格子ソースの現在の形式版,
        建物定義ID: 識別子を作る(識別子の綴り),
        表示名: "新しい建物".to_string(),
        入口のローカル方向: 建物の入口方向ソース { x: 0.0, z: 1.0 },
        格子: 升目の複体ソース {
            根の升目: 原点の座標(),
            升目一覧: vec![四面へ壁を入れた升目(原点の座標())],
        },
        装飾: 建物の装飾ソース {},
    }
}

pub(crate) fn 識別子を作る(綴り: &str) -> 建物定義ID {
    match 建物定義ID::生成する(綴り) {
        Ok(識別子) => 識別子,
        Err(原因) => panic!("試験の建物定義IDが空である: {原因}"),
    }
}

pub(crate) fn 原点の座標() -> 升目の座標ソース {
    升目の座標ソース { 横: 0, 奥: 0, 階: 0 }
}

pub(crate) fn 座標を作る(横: i32, 奥: i32, 階: u32) -> 升目の座標ソース {
    升目の座標ソース { 横, 奥, 階 }
}

pub(crate) fn 平壁を入れる() -> はめ口ソース {
    はめ口ソース::壁を入れる {
        壁の種類: 壁の種類ソース::平壁,
        外面の飾り: 壁の外面の飾りソース::付けない,
    }
}

pub(crate) fn 四面へ壁を入れた升目(座標: 升目の座標ソース) -> 升目ソース {
    升目ソース {
        座標,
        正面: はめ口ソース::壁を入れる {
            壁の種類: 壁の種類ソース::扉枠付きの壁,
            外面の飾り: 壁の外面の飾りソース::付けない,
        },
        背面: 平壁を入れる(),
        左面: はめ口ソース::壁を入れる {
            壁の種類: 壁の種類ソース::窓壁,
            外面の飾り: 壁の外面の飾りソース::付けない,
        },
        右面: 平壁を入れる(),
        床: 升目の床ソース::張る,
        屋根: 升目の屋根ソース::載せる,
    }
}

/// 4面とも壁を入れず、床も屋根も持たない升目。隣を継ぐ面を空けた形を作るときに使う。
pub(crate) fn 骨格だけの升目(座標: 升目の座標ソース) -> 升目ソース {
    升目ソース {
        座標,
        正面: はめ口ソース::入れない,
        背面: はめ口ソース::入れない,
        左面: はめ口ソース::入れない,
        右面: はめ口ソース::入れない,
        床: 升目の床ソース::張らない,
        屋根: 升目の屋根ソース::載せない,
    }
}
