//! 格子由来の建物定義: ソースを解いて検査を通したベイ格子と、その建物の名乗りを1件にまとめた値。
//!
//! ソースの型(`source`)と分けるのは、こちらが「検査を通った」ことを型で言うためである。ソースのまま
//! 台帳へ入れると、升目の宣言が破れている建物が台帳に並び、破れがカタログを組む段まで持ち越される。
//!
//! 用途を持たないのは、格子から組んだ建物がすべて家屋だからである。骨格見本は部品の噛み合いを見せる
//! ための宣言の規則の見本であり、人が升目を置いて作るものではない。

use blitz_assembly::ベイ格子;

use crate::runtime_compilation::{建物の入口方向, 建物定義ID};

#[derive(Debug, Clone, PartialEq)]
pub struct 格子由来の建物定義 {
    識別子: 建物定義ID,
    表示名: String,
    入口のローカル方向: 建物の入口方向,
    格子: ベイ格子,
}

impl 格子由来の建物定義 {
    /// ソースの解決だけが呼ぶ生成の口。検査を通ったベイ格子だけがここへ入る。
    pub(super) fn 解けた材料から生成する(
        識別子: 建物定義ID, 表示名: String, 入口のローカル方向: 建物の入口方向, 格子: ベイ格子
    ) -> Self {
        Self {
            識別子,
            表示名,
            入口のローカル方向,
            格子,
        }
    }

    pub fn 識別子(&self) -> &建物定義ID {
        &self.識別子
    }

    pub fn 表示名(&self) -> &str {
        &self.表示名
    }

    pub fn 入口のローカル方向(&self) -> 建物の入口方向 {
        self.入口のローカル方向
    }

    pub fn 格子(&self) -> &ベイ格子 {
        &self.格子
    }
}
