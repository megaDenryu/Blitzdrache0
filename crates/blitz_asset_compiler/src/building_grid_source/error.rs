//! 建物の格子のソースを読み、ベイ格子へ解くときに破れうる前提を枝で数え上げた失敗の型。
//!
//! 文面へ建物定義IDとパスを載せるのは、読み手が直す先のファイルを決めるためである。置き場には
//! 建物が何件も並ぶため、どれが落ちたかを言わないと直す先が分からない。

use blitz_assembly::ベイ格子エラー;

#[derive(Debug, thiserror::Error)]
pub enum 建物の格子のソースエラー {
    #[error("建物の格子の置き場{置き場}を読めない: {原因}")]
    置き場を読めない { 置き場: String, 原因: std::io::Error },

    #[error("建物の格子のファイル{パス}を読めない: {原因}")]
    ファイルを読めない { パス: String, 原因: std::io::Error },

    #[error("建物の格子のファイル{パス}をJSONとして解釈できない: {原因}")]
    Jsonを解釈できない { パス: String, 原因: serde_json::Error },

    #[error("建物の格子のファイル{パス}の形式版{版}には対応していない(対応版: 1から{対応上限}まで)")]
    形式版に対応していない { パス: String, 版: u32, 対応上限: u32 },

    #[error("建物の格子が名乗る識別子{ファイルが名乗る識別子}が、置き場のディレクトリ名{ディレクトリ名}と食い違う")]
    名乗る識別子がディレクトリ名と食い違う {
        ファイルが名乗る識別子: String,
        ディレクトリ名: String,
    },

    #[error("建物の格子{建物定義}の升目が成り立たない: {原因}")]
    升目が成り立たない { 建物定義: String, 原因: ベイ格子エラー },

    #[error("建物の格子{建物定義}の{欄}が不正である: {説明}")]
    欄が不正 {
        建物定義: String, 欄: &'static str, 説明: String
    },

    #[error("建物の格子{建物定義}を書き出せない: {原因}")]
    書き出せない { 建物定義: String, 原因: std::io::Error },

    #[error("建物の格子{建物定義}をJSONへ組み立てられない: {原因}")]
    Jsonを組み立てられない { 建物定義: String, 原因: serde_json::Error },
}
