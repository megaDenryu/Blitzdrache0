//! 建物の格子の台帳: 置き場に並ぶ格子を解いて、識別子の昇順で持つ表。
//!
//! カタログの組み立て係がこの台帳を保持するのは、組み立てのたびにディスクを読み直さないためであり、
//! 保存の検査が「この1件を差し替えたら組み立てが通るか」を正本を書き換える前に確かめられるようにするためである。
//!
//! 並びを昇順に固定するのは、同じ置き場からは常に同じ順のカタログが出ることを守るためである。
//! ディレクトリの読み取り順は実行環境に依り、順が変わるとカタログのバイト列が変わる。

use std::collections::BTreeMap;

use super::directory::建物の格子の置き場;
use super::error::建物の格子のソースエラー;
use super::grid_definition::格子由来の建物定義;
use crate::runtime_compilation::建物定義ID;

#[derive(Debug, Clone, Default, PartialEq)]
pub struct 建物の格子の台帳 {
    識別子ごとの定義: BTreeMap<建物定義ID, 格子由来の建物定義>,
}

impl 建物の格子の台帳 {
    pub fn 空から始める() -> Self {
        Self {
            識別子ごとの定義: BTreeMap::new(),
        }
    }

    /// 置き場の全建物を解いて台帳にする。1件でも解けなければ型付きエラーで拒み、残りを黙って読み飛ばさない。
    pub fn 置き場から読む(置き場: &建物の格子の置き場) -> Result<Self, 建物の格子のソースエラー> {
        let mut 台帳 = Self::空から始める();
        for 識別子 in 置き場.保存されている建物定義の識別子を昇順に数え上げる()? {
            let 定義 = 置き場.建物定義の格子ファイル(&識別子).読んで解く()?;
            if 定義.識別子() != &識別子 {
                return Err(建物の格子のソースエラー::名乗る識別子がディレクトリ名と食い違う {
                    ファイルが名乗る識別子: 定義.識別子().綴り().to_string(),
                    ディレクトリ名: 識別子.綴り().to_string(),
                });
            }
            台帳.定義を1件預ける(定義);
        }
        Ok(台帳)
    }

    /// 同じ識別子の定義が既にあれば差し替える。保存の検査が候補の1件を試すときにこの口を使う。
    pub fn 定義を1件預ける(&mut self, 定義: 格子由来の建物定義) {
        self.識別子ごとの定義.insert(定義.識別子().clone(), 定義);
    }

    pub fn 識別子で引く(&self, 識別子: &建物定義ID) -> Option<&格子由来の建物定義> {
        self.識別子ごとの定義.get(識別子)
    }

    pub fn 昇順に数え上げる(&self) -> impl Iterator<Item = &格子由来の建物定義> {
        self.識別子ごとの定義.values()
    }

    pub fn 件数(&self) -> usize {
        self.識別子ごとの定義.len()
    }
}
