//! 大域サンプル格子からチャンク1つ分の窓を切り出す工程。受け取るのは諸元・チャンク座標・大域サンプル添字から高さを返す関数であり、返すのは重なり込みの高さ格子である。
//! 隣接する2つのチャンクが共有する標本は同じ大域サンプル添字で引かれるため、境界の高さはこの切り出しだけで一致する。
//!
//! 大域サンプル添字をi16の範囲に限るのは、標本の位置を実数へ変換するときにi16からf32への変換だけが値を落とさないためである。
//! 範囲を超えた要求は無言で丸めず型付きエラーにする。

use blitz_engine::チャンク座標;

use super::error::高さ格子エラー;
use super::grid::{標本数をusizeへ変換する, 高さ格子};
use super::specification::高さ格子諸元;

pub fn 高さ格子を切り出す(
    諸元: 高さ格子諸元,
    チャンク: チャンク座標,
    大域高さを求める: impl Fn(i16, i16) -> f32,
) -> Result<高さ格子, 高さ格子エラー> {
    let 重なり = i32::from(諸元.重なり幅());
    let 上限 = 諸元.格子添字上限();
    let 基点x = 大域基点を求める(チャンク.x(), 諸元.辺分割数())?;
    let 基点z = 大域基点を求める(チャンク.z(), 諸元.辺分割数())?;
    let mut 高さ一覧 = Vec::with_capacity(標本数をusizeへ変換する(諸元)?);
    for 格子添字z in -重なり..=上限 {
        let 大域z = 大域添字を求める(基点z, 格子添字z, チャンク.z())?;
        for 格子添字x in -重なり..=上限 {
            let 大域x = 大域添字を求める(基点x, 格子添字x, チャンク.x())?;
            高さ一覧.push(大域高さを求める(大域x, 大域z));
        }
    }
    高さ格子::生成する(諸元, 高さ一覧)
}

/// チャンクの角にあたる大域サンプル添字。隣接チャンクの基点との差がちょうど辺分割数になるため、窓の縁が共有される。
fn 大域基点を求める(チャンク成分: i32, 辺分割数: u16) -> Result<i32, 高さ格子エラー> {
    チャンク成分
        .checked_mul(i32::from(辺分割数))
        .ok_or(高さ格子エラー::大域添字範囲外 { チャンク成分 })
}

fn 大域添字を求める(基点: i32, 格子添字: i32, チャンク成分: i32) -> Result<i16, 高さ格子エラー> {
    let 合計 = 基点.checked_add(格子添字).ok_or(高さ格子エラー::大域添字範囲外 { チャンク成分 })?;
    i16::try_from(合計).map_err(|_| 高さ格子エラー::大域添字範囲外 { チャンク成分 })
}
