//! ファイルのバイト列から高さ格子を復元する工程。固定識別値と形式版を先に確かめ、諸元の検証を通してから本体の長さを照合する。
//! 未知の版を無言で最新として読まないのは、標本の並びが変わったときに壊れた地形を黙って焼くことになるためである。

use std::path::Path;

use super::error::高さ格子エラー;
use super::grid::{標本数をusizeへ変換する, 高さ格子};
use super::specification::高さ格子諸元;
use super::{ヘッダー長, 固定識別値, 形式版};

pub fn 高さ格子を読み込む(パス: &Path) -> Result<高さ格子, 高さ格子エラー> {
    let バイト列 = std::fs::read(パス).map_err(|誤り| 高さ格子エラー::ファイル読込失敗(format!("{}: {誤り}", パス.display())))?;
    バイト列から復元する(&バイト列)
}

fn バイト列から復元する(バイト列: &[u8]) -> Result<高さ格子, 高さ格子エラー> {
    let ヘッダー = バイト列.get(0..ヘッダー長).ok_or(高さ格子エラー::ヘッダー不足 { 実長: バイト列.len() })?;
    if ヘッダー.get(0..8) != Some(固定識別値.as_slice()) {
        return Err(高さ格子エラー::固定識別値不一致);
    }
    let 版 = u32::from_le_bytes(ヘッダーの四バイト(ヘッダー, 8)?);
    if 版 != 形式版 {
        return Err(高さ格子エラー::未対応形式版(版));
    }
    let 諸元 = 諸元を読む(ヘッダー)?;
    let 期待本体長 = 標本数をusizeへ変換する(諸元)?.saturating_mul(4);
    let 本体 = バイト列.get(ヘッダー長..).unwrap_or_default();
    if 本体.len() != 期待本体長 {
        return Err(高さ格子エラー::本体長不一致 {
            期待: 期待本体長,
            実際: 本体.len(),
        });
    }
    高さ格子::生成する(諸元, 高さ一覧を読む(本体)?)
}

fn 諸元を読む(ヘッダー: &[u8]) -> Result<高さ格子諸元, 高さ格子エラー> {
    let 辺分割数 = u16::from_le_bytes([ヘッダーの一バイト(ヘッダー, 12)?, ヘッダーの一バイト(ヘッダー, 13)?]);
    let 重なり幅 = ヘッダーの一バイト(ヘッダー, 14)?;
    let 一辺メートル = f32::from_le_bytes(ヘッダーの四バイト(ヘッダー, 15)?);
    高さ格子諸元::生成する(辺分割数, 重なり幅, 一辺メートル)
}

fn 高さ一覧を読む(本体: &[u8]) -> Result<Vec<f32>, 高さ格子エラー> {
    let mut 結果 = Vec::with_capacity(本体.len() / 4);
    for 塊 in 本体.chunks_exact(4) {
        let 値 = <[u8; 4]>::try_from(塊).map_err(|_| 高さ格子エラー::本体長不一致 {
            期待: 4, 実際: 塊.len()
        })?;
        結果.push(f32::from_le_bytes(値));
    }
    Ok(結果)
}

fn ヘッダーの一バイト(ヘッダー: &[u8], 位置: usize) -> Result<u8, 高さ格子エラー> {
    ヘッダー.get(位置).copied().ok_or(高さ格子エラー::ヘッダー不足 { 実長: ヘッダー.len() })
}

fn ヘッダーの四バイト(ヘッダー: &[u8], 位置: usize) -> Result<[u8; 4], 高さ格子エラー> {
    let 範囲 = ヘッダー
        .get(位置..位置.saturating_add(4))
        .ok_or(高さ格子エラー::ヘッダー不足 { 実長: ヘッダー.len() })?;
    <[u8; 4]>::try_from(範囲).map_err(|_| 高さ格子エラー::ヘッダー不足 { 実長: ヘッダー.len() })
}
