//! 高さ格子の実体。重なりを含む正方窓の標本を行優先(Zが外側、Xが内側)で保持し、格子添字での読み出しを提供する。
//! 格子添字は重なりの分だけ負の側へ伸びており、有効範囲は`-重なり幅`から`辺分割数 + 重なり幅`までである。

use super::error::高さ格子エラー;
use super::specification::高さ格子諸元;

#[derive(Debug, Clone, PartialEq)]
pub struct 高さ格子 {
    諸元: 高さ格子諸元,
    高さ一覧: Vec<f32>,
}

impl 高さ格子 {
    pub fn 生成する(諸元: 高さ格子諸元, 高さ一覧: Vec<f32>) -> Result<Self, 高さ格子エラー> {
        let 期待 = 標本数をusizeへ変換する(諸元)?;
        if 高さ一覧.len() != 期待 {
            return Err(高さ格子エラー::標本数不一致 {
                期待, 実際: 高さ一覧.len()
            });
        }
        Ok(Self { 諸元, 高さ一覧 })
    }

    pub fn 諸元(&self) -> 高さ格子諸元 {
        self.諸元
    }

    pub fn 高さ一覧(&self) -> &[f32] {
        &self.高さ一覧
    }

    /// 格子添字で高さメートルを引く。範囲外は型付きエラーにする。
    pub fn 高さ(&self, 格子添字x: i32, 格子添字z: i32) -> Result<f32, 高さ格子エラー> {
        let 添字 = 配列添字を求める(self.諸元, 格子添字x, 格子添字z)?;
        self.高さ一覧.get(添字).copied().ok_or(高さ格子エラー::格子添字範囲外 {
            x: 格子添字x, z: 格子添字z
        })
    }
}

pub(super) fn 標本数をusizeへ変換する(諸元: 高さ格子諸元) -> Result<usize, 高さ格子エラー> {
    let 標本数 = 諸元.標本数();
    usize::try_from(標本数).map_err(|_| 高さ格子エラー::標本数表現不能(標本数))
}

fn 配列添字を求める(諸元: 高さ格子諸元, 格子添字x: i32, 格子添字z: i32) -> Result<usize, 高さ格子エラー> {
    let 重なり = i32::from(諸元.重なり幅());
    let 上限 = 諸元.格子添字上限();
    let 範囲外 = 高さ格子エラー::格子添字範囲外 {
        x: 格子添字x, z: 格子添字z
    };
    if 格子添字x < -重なり || 格子添字x > 上限 || 格子添字z < -重なり || 格子添字z > 上限 {
        return Err(範囲外);
    }
    let 辺 = i32::try_from(諸元.保存辺長()).map_err(|_| 高さ格子エラー::標本数表現不能(諸元.標本数()))?;
    let 位置 = (格子添字z + 重なり) * 辺 + (格子添字x + 重なり);
    usize::try_from(位置).map_err(|_| 範囲外)
}
