//! 高さ格子ソース形式の型付きエラー。諸元の検証・格子添字の範囲・ファイル形式の3つの失敗をこの1つの語彙で表す。

use thiserror::Error;

#[derive(Debug, Error)]
pub enum 高さ格子エラー {
    #[error("辺分割数が2の冪でない: {0}")]
    辺分割数が2の冪でない(u16),
    #[error("辺分割数が上限{上限}を超えている: {実値}")]
    辺分割数過大 { 実値: u16, 上限: u16 },
    #[error("重なり幅は1以上でなければならない")]
    重なり幅なし,
    #[error("重なり幅が上限{上限}を超えている: {実値}")]
    重なり幅過大 { 実値: u8, 上限: u8 },
    #[error("チャンクの一辺メートルが正の有限値でない: {0}")]
    一辺メートル不正(f32),
    #[error("標本数が諸元と合わない: 期待{期待}、実際{実際}")]
    標本数不一致 { 期待: usize, 実際: usize },
    #[error("標本数をこの処理系のusizeで表せない: {0}")]
    標本数表現不能(u32),
    #[error("格子添字が有効範囲の外である: X={x}、Z={z}")]
    格子添字範囲外 { x: i32, z: i32 },
    #[error("頂点数がこの形式で表せる範囲を超えた: {0}")]
    頂点数表現不能(usize),
    #[error("大域サンプル添字がi16の範囲を超えた: チャンク成分={チャンク成分}")]
    大域添字範囲外 { チャンク成分: i32 },
    #[error("高さ格子ファイルの読込に失敗した: {0}")]
    ファイル読込失敗(String),
    #[error("高さ格子のヘッダーが足りない: 実長{実長}バイト")]
    ヘッダー不足 { 実長: usize },
    #[error("高さ格子の固定識別値が一致しない")]
    固定識別値不一致,
    #[error("未対応の高さ格子形式版だった: {0}")]
    未対応形式版(u32),
    #[error("高さ格子の本体長が諸元と合わない: 期待{期待}バイト、実際{実際}バイト")]
    本体長不一致 { 期待: usize, 実際: usize },
}
