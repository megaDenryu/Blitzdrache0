//! 高さ格子の諸元。格子の細かさ・隣接と重なる縁の幅・チャンクの一辺長を持ち、格子点数と保存する標本数を導出する。
//! 値の検証をこの型へ集めるため、格子の実体は標本数が諸元と合うことだけを確かめればよい。

use super::error::高さ格子エラー;

/// 辺分割数の上限。1チャンクを4096分割すれば格子点は4097×4097であり、地形1チャンクの物量として十分に上回る。
/// 上限を置くと、保存辺長の二乗が32ビット整数へ収まることが型の範囲だけで分かる。
const 辺分割数上限: u16 = 4096;

/// 重なり幅の上限。中央差分の法線には1点あれば足り、2倍刻みで段を粗くしても数点で足りる。
const 重なり幅上限: u8 = 16;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 高さ格子諸元 {
    辺分割数: u16,
    重なり幅: u8,
    一辺メートル: f32,
}

impl 高さ格子諸元 {
    /// 辺分割数を2の冪に限るのは、格子点数が2^n+1になり、1つおきに間引いた点がそのまま次に粗い段の格子点になるためである。
    pub fn 生成する(辺分割数: u16, 重なり幅: u8, 一辺メートル: f32) -> Result<Self, 高さ格子エラー> {
        if !辺分割数.is_power_of_two() {
            return Err(高さ格子エラー::辺分割数が2の冪でない(辺分割数));
        }
        if 辺分割数 > 辺分割数上限 {
            return Err(高さ格子エラー::辺分割数過大 {
                実値: 辺分割数,
                上限: 辺分割数上限,
            });
        }
        if 重なり幅 == 0 {
            return Err(高さ格子エラー::重なり幅なし);
        }
        if 重なり幅 > 重なり幅上限 {
            return Err(高さ格子エラー::重なり幅過大 {
                実値: 重なり幅,
                上限: 重なり幅上限,
            });
        }
        if !一辺メートル.is_finite() || 一辺メートル <= 0.0 {
            return Err(高さ格子エラー::一辺メートル不正(一辺メートル));
        }
        Ok(Self {
            辺分割数,
            重なり幅,
            一辺メートル,
        })
    }

    pub fn 辺分割数(&self) -> u16 {
        self.辺分割数
    }

    pub fn 重なり幅(&self) -> u8 {
        self.重なり幅
    }

    pub fn 一辺メートル(&self) -> f32 {
        self.一辺メートル
    }

    /// 重なりを含めない1辺の格子点数。
    pub fn 格子点数(&self) -> u32 {
        u32::from(self.辺分割数) + 1
    }

    /// 重なりを両側へ足した、保存する1辺の標本数。
    pub fn 保存辺長(&self) -> u32 {
        self.格子点数() + 2 * u32::from(self.重なり幅)
    }

    pub fn 標本数(&self) -> u32 {
        self.保存辺長() * self.保存辺長()
    }

    /// 隣り合う格子点の距離。
    pub fn 刻みメートル(&self) -> f32 {
        self.一辺メートル / f32::from(self.辺分割数)
    }

    /// 格子添字として有効な最大値。最小値はこれの符号を反転した重なり幅である。
    pub fn 格子添字上限(&self) -> i32 {
        i32::from(self.辺分割数) + i32::from(self.重なり幅)
    }
}
