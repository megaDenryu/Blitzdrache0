//! 地表材質の重み格子: チャンク1つ分の地表を4層(草・泥・岩・砂)でどう塗り分けたかを持つソース形式。
//! 標本は高さ格子の格子点と1対1で並び、1標本あたり4層ぶんのu8を持つ。
//! 形式の作法は高さ格子と揃える(固定識別値・形式版・諸元・本体の順)。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`

mod error;
#[cfg(test)]
mod format_tests;
mod grid;
mod read;
mod specification;
mod write;

pub use error::地表材質の重み格子エラー;
pub use grid::地表材質の重み格子;
pub use read::地表材質の重み格子を読み込む;
pub use specification::地表材質の重み格子諸元;
pub use write::地表材質の重み格子を格納する;

/// ファイル先頭の固定識別値。別形式のバイト列を重みの並びとして読み進めないための識別子である。
pub(crate) const 固定識別値: [u8; 8] = *b"BLITZSMW";

pub(crate) const 形式版: u32 = 1;

/// 塗り分けの層の数。草・泥・岩・砂の4層であり、エディターの編集モデルとエンジンの地表の枝が同じ数を持つ。
/// 層を増やすときは形式版を上げる(1標本あたりのバイト数が変わり、既存のファイルを読み替えられないためである)。
pub const 地表材質の層数: usize = 4;

/// 固定識別値8 + 形式版4 + 一辺の標本数4 + 層数1 の合計。
/// 幅の違う整数を並べて詰め物を置かないのは、詰め物が「未設定の値」として形式へ入り込むためである。
pub(crate) const ヘッダー長: usize = 17;
