//! ファイルのバイト列から地表材質の重み格子を復元する工程。固定識別値と形式版と層数を先に確かめ、
//! 諸元の検証を通してから本体の長さを照合する。
//! 未知の版を無言で最新として読まないのは、標本の並びが変わったときに壊れた塗り分けを黙って焼くことになるためである。

use std::path::Path;

use super::error::地表材質の重み格子エラー;
use super::grid::地表材質の重み格子;
use super::specification::地表材質の重み格子諸元;
use super::{ヘッダー長, 固定識別値, 地表材質の層数, 形式版};

pub fn 地表材質の重み格子を読み込む(パス: &Path) -> Result<地表材質の重み格子, 地表材質の重み格子エラー> {
    let バイト列 =
        std::fs::read(パス).map_err(|誤り| 地表材質の重み格子エラー::ファイル読込失敗(format!("{}: {誤り}", パス.display())))?;
    バイト列から復元する(&バイト列)
}

pub(super) fn バイト列から復元する(バイト列: &[u8]) -> Result<地表材質の重み格子, 地表材質の重み格子エラー> {
    let ヘッダー = バイト列
        .get(0..ヘッダー長)
        .ok_or(地表材質の重み格子エラー::ヘッダー不足 { 実長: バイト列.len() })?;
    if ヘッダー.get(0..8) != Some(固定識別値.as_slice()) {
        return Err(地表材質の重み格子エラー::固定識別値不一致);
    }
    let 版 = u32::from_le_bytes(ヘッダーの四バイト(ヘッダー, 8)?);
    if 版 != 形式版 {
        return Err(地表材質の重み格子エラー::未対応形式版(版));
    }
    let 諸元 = 地表材質の重み格子諸元::生成する(u32::from_le_bytes(ヘッダーの四バイト(ヘッダー, 12)?))?;
    let 記録された層数 = usize::from(ヘッダーの一バイト(ヘッダー, 16)?);
    if 記録された層数 != 地表材質の層数 {
        return Err(地表材質の重み格子エラー::層数不一致 {
            期待: 地表材質の層数,
            実際: 記録された層数,
        });
    }
    let 本体 = バイト列.get(ヘッダー長..).unwrap_or_default();
    地表材質の重み格子::生成する(諸元, 本体.to_vec())
}

fn ヘッダーの一バイト(ヘッダー: &[u8], 位置: usize) -> Result<u8, 地表材質の重み格子エラー> {
    ヘッダー
        .get(位置)
        .copied()
        .ok_or(地表材質の重み格子エラー::ヘッダー不足 { 実長: ヘッダー.len() })
}

fn ヘッダーの四バイト(ヘッダー: &[u8], 位置: usize) -> Result<[u8; 4], 地表材質の重み格子エラー> {
    let 範囲 = ヘッダー
        .get(位置..位置.saturating_add(4))
        .ok_or(地表材質の重み格子エラー::ヘッダー不足 { 実長: ヘッダー.len() })?;
    <[u8; 4]>::try_from(範囲).map_err(|_| 地表材質の重み格子エラー::ヘッダー不足 { 実長: ヘッダー.len() })
}
