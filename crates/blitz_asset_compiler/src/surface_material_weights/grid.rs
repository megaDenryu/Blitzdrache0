//! 地表材質の重み格子の実体。標本を行優先(Zが外側、Xが内側)で保持し、標本の添字での読み出しを提供する。
//! 標本の添字は0から`一辺の標本数 - 1`までであり、Zが0の行がチャンクの北端(ワールドの-Z側)である。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`

use super::error::地表材質の重み格子エラー;
use super::specification::地表材質の重み格子諸元;
use super::地表材質の層数;

/// 塗られていないチャンクを表す重み。先頭の層(草)だけが満量であり、合計は255である。
const 先頭の層だけの重み: [u8; 地表材質の層数] = [255, 0, 0, 0];

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 地表材質の重み格子 {
    諸元: 地表材質の重み格子諸元,
    重み一覧: Vec<u8>,
}

impl 地表材質の重み格子 {
    pub fn 生成する(諸元: 地表材質の重み格子諸元, 重み一覧: Vec<u8>) -> Result<Self, 地表材質の重み格子エラー> {
        let 期待 = 諸元.本体のバイト数()?;
        if 重み一覧.len() != 期待 {
            return Err(地表材質の重み格子エラー::バイト数不一致 {
                期待, 実際: 重み一覧.len()
            });
        }
        Ok(Self { 諸元, 重み一覧 })
    }

    /// まだ一度も塗られていないチャンクの格子。エディターが重みを保存していない場合と、
    /// 重みを持たない形式版1のチャンクソースを最新へ変換した場合の両方がこの1つを通る。
    pub fn 先頭の層だけで塗り潰して生成する(
        諸元: 地表材質の重み格子諸元
    ) -> Result<Self, 地表材質の重み格子エラー> {
        let バイト数 = 諸元.本体のバイト数()?;
        let 標本数 = バイト数 / 地表材質の層数;
        let mut 重み一覧 = Vec::with_capacity(バイト数);
        for _ in 0..標本数 {
            重み一覧.extend_from_slice(&先頭の層だけの重み);
        }
        Self::生成する(諸元, 重み一覧)
    }

    pub fn 諸元(&self) -> 地表材質の重み格子諸元 {
        self.諸元
    }

    pub fn バイト列(&self) -> &[u8] {
        &self.重み一覧
    }

    /// 標本1つ分の層ごとの重みを参照する。範囲外は型付きエラーにする。
    pub fn 標本の重み(
        &self, 標本添字x: u32, 標本添字z: u32
    ) -> Result<[u8; 地表材質の層数], 地表材質の重み格子エラー> {
        let 範囲外 = || 地表材質の重み格子エラー::標本添字範囲外 {
            x: 標本添字x, z: 標本添字z
        };
        let 一辺 = self.諸元.一辺の標本数();
        if 標本添字x >= 一辺 || 標本添字z >= 一辺 {
            return Err(範囲外());
        }
        let 行の先頭 = usize::try_from(標本添字z)
            .ok()
            .and_then(|z| z.checked_mul(usize::try_from(一辺).ok()?))
            .ok_or_else(範囲外)?;
        let 標本番号 = usize::try_from(標本添字x).ok().and_then(|x| 行の先頭.checked_add(x)).ok_or_else(範囲外)?;
        let 開始 = 標本番号.checked_mul(地表材質の層数).ok_or_else(範囲外)?;
        self.重み一覧
            .get(開始..開始.saturating_add(地表材質の層数))
            .and_then(|範囲| <[u8; 地表材質の層数]>::try_from(範囲).ok())
            .ok_or_else(範囲外)
    }

    /// 同じチャンクの高さ格子と標本が1対1で並ぶことを確かめる。食い違ったまま焼くと、
    /// 塗り分けが地形の上を等倍でなく引き伸ばされて載る。
    pub fn 高さ格子の格子点数と一致することを確かめる(
        &self,
        高さ格子の格子点数: u32,
    ) -> Result<(), 地表材質の重み格子エラー> {
        if self.諸元.一辺の標本数() == 高さ格子の格子点数 {
            return Ok(());
        }
        Err(地表材質の重み格子エラー::高さ格子と標本数が食い違う {
            重みの一辺: self.諸元.一辺の標本数(),
            高さの一辺: 高さ格子の格子点数,
        })
    }
}
