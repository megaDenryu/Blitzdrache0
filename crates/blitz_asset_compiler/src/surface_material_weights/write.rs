//! 地表材質の重み格子をファイルのバイト列へ格納する工程。ヘッダーに諸元、本体に重みを標本の保持順のまま並べる。
//! 走査順は格子の保持順(Zが外側、Xが内側)をそのまま使うため、同じ格子からは常に同じバイト列を得る。

use super::grid::地表材質の重み格子;
use super::{ヘッダー長, 固定識別値, 地表材質の層数, 形式版};

pub fn 地表材質の重み格子を格納する(格子: &地表材質の重み格子) -> Vec<u8> {
    let 本体 = 格子.バイト列();
    let mut バイト列 = Vec::with_capacity(ヘッダー長.saturating_add(本体.len()));
    バイト列.extend_from_slice(&固定識別値);
    バイト列.extend_from_slice(&形式版.to_le_bytes());
    バイト列.extend_from_slice(&格子.諸元().一辺の標本数().to_le_bytes());
    バイト列.push(層数のバイト());
    バイト列.extend_from_slice(本体);
    バイト列
}

/// 層数を1バイトへ収める。上限は形式の定数であり、収まらない値はこの形式を書けないことを意味するため、
/// 到達したらプログラムのバグである。
fn 層数のバイト() -> u8 {
    u8::try_from(地表材質の層数).unwrap_or_else(|_| panic!("地表材質の層数が1バイトへ収まるという不変条件に違反した: {地表材質の層数}"))
}
