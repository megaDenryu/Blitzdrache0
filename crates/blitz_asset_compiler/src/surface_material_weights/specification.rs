//! 地表材質の重み格子の諸元。一辺の標本数だけを持ち、標本数と本体のバイト数を導出する。
//! 値の検証をこの型へ集めるため、格子の実体はバイト数が諸元と合うことだけを確かめればよい。

use super::error::地表材質の重み格子エラー;
use super::地表材質の層数;

/// 一辺の標本数の上限。高さ格子の辺分割数の上限4096に格子点の1を足した値であり、
/// 地形1チャンクの塗り分けの細かさとして十分に上回る。上限を置くと、本体のバイト数が
/// 64ビット整数へ収まることが型の範囲だけで分かる。
const 一辺の標本数の上限: u32 = 4097;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 地表材質の重み格子諸元 {
    一辺の標本数: u32,
}

impl 地表材質の重み格子諸元 {
    /// 標本は高さ格子の格子点と1対1で並ぶため、一辺は2以上である(1点だけの格子は面を張れない)。
    pub fn 生成する(一辺の標本数: u32) -> Result<Self, 地表材質の重み格子エラー> {
        if 一辺の標本数 < 2 {
            return Err(地表材質の重み格子エラー::一辺の標本数が過少(一辺の標本数));
        }
        if 一辺の標本数 > 一辺の標本数の上限 {
            return Err(地表材質の重み格子エラー::一辺の標本数が過大 {
                実値: 一辺の標本数,
                上限: 一辺の標本数の上限,
            });
        }
        Ok(Self { 一辺の標本数 })
    }

    pub fn 一辺の標本数(self) -> u32 {
        self.一辺の標本数
    }

    /// 本体に並べる重みのバイト数。1標本につき層数ぶんのu8を持つ。
    pub fn 本体のバイト数(self) -> Result<usize, 地表材質の重み格子エラー> {
        let 一辺 = usize::try_from(self.一辺の標本数).map_err(|_| 地表材質の重み格子エラー::バイト数表現不能 {
            一辺の標本数: self.一辺の標本数,
        })?;
        一辺.checked_mul(一辺).and_then(|標本数| 標本数.checked_mul(地表材質の層数)).ok_or(
            地表材質の重み格子エラー::バイト数表現不能 {
                一辺の標本数: self.一辺の標本数,
            },
        )
    }
}
