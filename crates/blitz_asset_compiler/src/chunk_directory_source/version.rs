//! 版ごとの形式宣言を最新のチャンク一辺へ変換する。

use blitz_engine::チャンク一辺;

use crate::error::アセットコンパイルエラー;

const 形式名: &str = "blitz_chunk_directory";

pub(super) fn 最新の一辺へ変換する(宣言行: &str) -> Result<チャンク一辺, アセットコンパイルエラー> {
    let 欄一覧: Vec<&str> = 宣言行.split_whitespace().collect();
    match 欄一覧.as_slice() {
        [形式名の欄, "1"] if *形式名の欄 == 形式名 => 版1の宣言.最新へ変換する(),
        [形式名の欄, "2", 一辺の欄] if *形式名の欄 == 形式名 => 版2の宣言::解析する(一辺の欄)?.最新へ変換する(),
        [形式名の欄, "2", ..] if *形式名の欄 == 形式名 => Err(アセットコンパイルエラー::チャンク目録ソース形式不正(宣言行.to_string())),
        [形式名の欄, 版, ..] if *形式名の欄 == 形式名 => Err(アセットコンパイルエラー::チャンク目録ソース未対応版((*版).to_string())),
        _ => Err(アセットコンパイルエラー::チャンク目録ソース形式不正(
            宣言行.to_string(),
        )),
    }
}

struct 版1の宣言;

impl 版1の宣言 {
    fn 最新へ変換する(self) -> Result<チャンク一辺, アセットコンパイルエラー> {
        チャンク一辺::生成する(100.0).map_err(アセットコンパイルエラー::チャンク一辺不正)
    }
}

struct 版2の宣言 {
    一辺メートル: f32,
}

impl 版2の宣言 {
    fn 解析する(欄: &str) -> Result<Self, アセットコンパイルエラー> {
        let 一辺メートル = 欄
            .parse::<f32>()
            .map_err(|_| アセットコンパイルエラー::チャンク目録ソース形式不正(欄.to_string()))?;
        Ok(Self { 一辺メートル })
    }

    fn 最新へ変換する(self) -> Result<チャンク一辺, アセットコンパイルエラー> {
        チャンク一辺::生成する(self.一辺メートル).map_err(アセットコンパイルエラー::チャンク一辺不正)
    }
}
