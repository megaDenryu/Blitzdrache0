//! 版ごとの形式宣言を最新のチャンク一辺へ変換する。

#[cfg(test)]
mod tests;

use blitz_engine::チャンク一辺;

use crate::error::チャンク目録コンパイルエラー;

const 形式名: &str = "blitz_chunk_directory";

pub(super) fn 宣言行を最新の一辺へ変換する(宣言行: &str) -> Result<チャンク一辺, チャンク目録コンパイルエラー> {
    let 欄一覧: Vec<&str> = 宣言行.split_whitespace().collect();
    match 欄一覧.as_slice() {
        [形式名の欄, "1"] if *形式名の欄 == 形式名 => 版1の宣言.最新へ変換する(),
        [形式名の欄, "2", 一辺の欄] if *形式名の欄 == 形式名 => 版2の宣言::解析する(一辺の欄)?.最新へ変換する(),
        [形式名の欄, "1", ..] if *形式名の欄 == 形式名 => {
            Err(チャンク目録コンパイルエラー::形式宣言不正(宣言行.to_string()))
        }
        [形式名の欄, "2", ..] if *形式名の欄 == 形式名 => {
            Err(チャンク目録コンパイルエラー::形式宣言不正(宣言行.to_string()))
        }
        [形式名の欄, 版, ..] if *形式名の欄 == 形式名 => {
            Err(チャンク目録コンパイルエラー::未対応版((*版).to_string()))
        }
        _ => Err(チャンク目録コンパイルエラー::形式宣言不正(宣言行.to_string())),
    }
}

struct 版1の宣言;

impl 版1の宣言 {
    fn 最新へ変換する(self) -> Result<チャンク一辺, チャンク目録コンパイルエラー> {
        チャンク一辺::生成する(100.0).map_err(チャンク目録コンパイルエラー::チャンク一辺不正)
    }
}

struct 版2の宣言 {
    一辺メートル: f32,
}

impl 版2の宣言 {
    fn 解析する(欄: &str) -> Result<Self, チャンク目録コンパイルエラー> {
        let 一辺メートル = 欄
            .parse::<f32>()
            .map_err(|_| チャンク目録コンパイルエラー::形式宣言不正(欄.to_string()))?;
        Ok(Self { 一辺メートル })
    }

    fn 最新へ変換する(self) -> Result<チャンク一辺, チャンク目録コンパイルエラー> {
        チャンク一辺::生成する(self.一辺メートル).map_err(チャンク目録コンパイルエラー::チャンク一辺不正)
    }
}
