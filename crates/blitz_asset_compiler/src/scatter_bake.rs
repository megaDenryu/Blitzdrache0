//! 地面へ散らす原型を焼くかどうかの指定と、プロセス境界でそれを運ぶ綴り。
//!
//! 既定を「焼く」にするのは、散布が世界の絵の一部だからである。遊ぶ世界も検収の世界も同じ絵で走らせ、
//! 焼かない側を明示で選ぶ。既定を逆にすると、指定を書き忘れた実行が黙って散布の無い絵を作る。
//!
//! この指定が要るのは、散布を入れた前後の絵を突き合わせる検収が「同じバイナリで焼き方の指定だけを分ける」
//! 形でなければならないためである。対照を散布より前のコミットから焼くと、比べている差へ散布以外の
//! コミットの差が混ざり、しかもその混ざりは絵から見分けられない。
//!
//! 注意: この指定は焼き方の指定へ載り、生成台帳の見出しの一部になる。したがって指定を変えた実行は、
//! 材料が同じでもチャンクを焼き直す。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「第6段階」

/// 地面へ散らす原型を焼くかどうか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 散布の焼き方 {
    焼く,
    焼かない,
}

/// 引数の並びでこの指定を導く綴り。値を続けず、在ることが「焼かない」を意味する。
const 選択肢の綴り: &str = "--no-scatter";

impl 散布の焼き方 {
    /// 引数の並びからこの指定を取り除き、指定と残りの引数を返す。綴りが無ければ既定の「焼く」である。
    pub fn 引数一覧から取り出す(引数一覧: &[String]) -> (Self, Vec<String>) {
        let 残り: Vec<String> = 引数一覧.iter().filter(|引数| 引数.as_str() != 選択肢の綴り).cloned().collect();
        if 残り.len() == 引数一覧.len() {
            (Self::焼く, 残り)
        } else {
            (Self::焼かない, 残り)
        }
    }

    /// 焼かせない側が引数の並びへ足す綴り。焼くときは1語も足さない。
    pub fn 引数へ足す綴り(self) -> Option<&'static str> {
        match self {
            Self::焼く => None,
            Self::焼かない => Some(選択肢の綴り),
        }
    }

    /// 焼き方の指定の綴りへ載せる語。生成台帳の見出しの一部になる。
    pub fn 台帳へ載せる綴り(self) -> &'static str {
        match self {
            Self::焼く => "焼く",
            Self::焼かない => "焼かない",
        }
    }

    /// 宣言の一覧をこの指定で絞る。焼かないときは空の一覧になり、チャンクは地面と固定物だけになる。
    /// 宣言そのものを消さずここで絞るのは、絵の対照が「同じ宣言のまま散布だけを外した世界」でなければ
    /// 差の原因を散布へ帰属できないためである。
    pub fn 適用する<宣言型>(self, 宣言一覧: &[宣言型]) -> &[宣言型] {
        match self {
            Self::焼く => 宣言一覧,
            Self::焼かない => &[],
        }
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::散布の焼き方;

    #[test]
    fn 綴りが無ければ焼く() {
        let 引数 = vec!["assets".to_string(), "target/x".to_string()];
        let (焼き方, 残り) = 散布の焼き方::引数一覧から取り出す(&引数);
        assert_eq!(焼き方, 散布の焼き方::焼く);
        assert_eq!(残り, 引数);
    }

    #[test]
    fn 綴りが在れば焼かず引数から取り除く() {
        let 引数 = vec!["assets".to_string(), "--no-scatter".to_string(), "target/x".to_string()];
        let (焼き方, 残り) = 散布の焼き方::引数一覧から取り出す(&引数);
        assert_eq!(焼き方, 散布の焼き方::焼かない);
        assert_eq!(残り, vec!["assets".to_string(), "target/x".to_string()]);
    }

    #[test]
    fn 足す綴りと取り出しが往復する() {
        for 焼き方 in [散布の焼き方::焼く, 散布の焼き方::焼かない] {
            let 引数: Vec<String> = 焼き方.引数へ足す綴り().into_iter().map(str::to_string).collect();
            assert_eq!(散布の焼き方::引数一覧から取り出す(&引数).0, 焼き方);
        }
    }

    #[test]
    fn 焼かないときは宣言の一覧が空になる() {
        let 宣言一覧 = [1_u8, 2, 3];
        assert_eq!(散布の焼き方::焼く.適用する(&宣言一覧), &宣言一覧);
        assert!(散布の焼き方::焼かない.適用する(&宣言一覧).is_empty());
    }
}
