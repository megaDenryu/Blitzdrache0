//! 地面へ置く1種の配置列を決める工程。受け取るのは高さ格子と所有チャンクと配置の混合の通し番号と配置の種と様式、
//! 返すのはチャンクの基準原点からの相対の配置列である。
//!
//! 値は群の種と添字だけから決まる混合関数で作るため、同じ宣言からは常に同じ配置列を得る。群の種へ通し番号を
//! 混ぜるのは、様式が同じ2つの種が同じ並びになると同じ場所に別の物が重なって立つためである。世界の乱数の種を
//! 混ぜるのは、同じ宣言でも種を変えれば別の世界になるためであり、種を持たない世界では恒等であるから
//! 既存の検証用の世界の配置は動かない。
//!
//! 平行移動のYを地表高さにするのは、原型が接地面をy=0に持ち、その値がそのまま接地面になるためである。
//! 見本の集落の内側でなくここに置くのは、同じ様式を世界の規模の散布が使うためである。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「判断j」

