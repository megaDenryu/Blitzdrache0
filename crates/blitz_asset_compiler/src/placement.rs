/// 混合関数の固定の種。世界を変えない限り同じ値を使い、同じ宣言から同じバイト列を得る。
const 種: u64 = 0x5669_6C6C_6167_6531;

/// 種の通し番号を混ぜるときに掛ける奇数。黄金比を64ビットへ写した値であり、隣り合う通し番号を遠くへ散らす。
const 通し番号を散らす奇数: u64 = 0x9E37_79B9_7F4A_7C15;

/// 1種をどう置くか。個体数を決めてから並べる形と、密度場で置く置かないを決める形の2つに分かれる。
/// 個体数を前者の側だけが持つのは、後者が個体数を宣言せず密度から決めるためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 配置様式 {
    個数を決めて並べる(個数を決める並べ方),
    密度場で散らす(密度場の散布),
}

/// 部品で組んだ個体の根をどこへ置くかの走査。原型を散らす様式とまったく同じ工程を通す。
/// 根の配置列を返すところで止めるのは、この先の展開が部品ごとの配置の集約という別の形になるためである。
pub(crate) fn 根の配置列を散らす(
    格子: &高さ格子,
    所有チャンク: チャンク座標,
    通し番号: 配置の混合の通し番号,
    配置の種: 配置の種,
    指定: 密度場の散布,
) -> Result<Vec<個体配置>, アセットコンパイルエラー> {
    let 群の種 = 群の種を混ぜる(所有チャンク, 通し番号, 配置の種);
    density_scatter::密度場で散らした配置列を作る(格子, 所有チャンク, 群の種, 配置の種, 指定)
}

pub(crate) fn 配置列を作る(
    格子: &高さ格子,
    所有チャンク: チャンク座標,
    通し番号: 配置の混合の通し番号,
    配置の種: 配置の種,
    様式: 配置様式,
) -> Result<Vec<個体配置>, アセットコンパイルエラー> {
    let 群の種 = 群の種を混ぜる(所有チャンク, 通し番号, 配置の種);
    match 様式 {
        配置様式::個数を決めて並べる(並べ方) => fixed_count::個数を決めて並べた配置列を作る(格子, 群の種, 並べ方),
        配置様式::密度場で散らす(指定) => {
            density_scatter::密度場で散らした配置列を作る(格子, 所有チャンク, 群の種, 配置の種, 指定)
        }
    }
}

/// 1つの種の配置を決める混合の種。チャンクと一覧の中での順番と世界の種から作る。
/// 原型を散らす様式と部品で組む散布が同じ口を通るのは、同じ世界の木と岩が同じ格子の上に乗るためである。
fn 群の種を混ぜる(所有チャンク: チャンク座標, 通し番号: 配置の混合の通し番号, 配置の種: 配置の種) -> u64 {
    種 ^ 所有チャンク.番号を返す() ^ 通し番号.混合へ入れる値().wrapping_mul(通し番号を散らす奇数) ^ 配置の種.混合へ足す値()
}
