//! 貼り合わせた格子の標本を並べる工程。受け取るのはチャンクの矩形と高さ格子の諸元と座標からの索引、
//! 返すのは南が外側・東が内側の昇順に並んだ高さの列である。
//!
//! 大域の格子添字をチャンクと格子内の添字へ分ける工程は`axis_split`が持つ。

use std::collections::HashMap;

use blitz_engine::チャンク座標;
use blitz_math::メートル;

use super::axis_split::大域の格子添字をチャンクと格子内へ分ける;
use super::chunk_rectangle::チャンクの矩形;
use super::error::高さ場コンパイルエラー;
use crate::height_grid::{高さ格子, 高さ格子諸元};

pub(super) struct 貼り合わせた格子の並び<'格子> {
    矩形: チャンクの矩形,
    辺分割数: u32,
    索引: HashMap<チャンク座標, &'格子 高さ格子>,
    東方向のチャンク数: u32,
    南方向のチャンク数: u32,
}

impl<'格子> 貼り合わせた格子の並び<'格子> {
    pub(super) fn 生成する(
        矩形: チャンクの矩形,
        格子の諸元: 高さ格子諸元,
        索引: HashMap<チャンク座標, &'格子 高さ格子>,
    ) -> Result<Self, 高さ場コンパイルエラー> {
        Ok(Self {
            東方向のチャンク数: 矩形.東方向のチャンク数()?,
            南方向のチャンク数: 矩形.南方向のチャンク数()?,
            辺分割数: u32::from(格子の諸元.辺分割数()),
            矩形,
            索引,
        })
    }

    pub(super) fn 東方向の格子点数(&self) -> Result<u32, 高さ場コンパイルエラー> {
        チャンク数と辺分割数から格子点数を求める(self.東方向のチャンク数, self.辺分割数)
    }

    pub(super) fn 南方向の格子点数(&self) -> Result<u32, 高さ場コンパイルエラー> {
        チャンク数と辺分割数から格子点数を求める(self.南方向のチャンク数, self.辺分割数)
    }

    pub(super) fn 標本を並べる(&self) -> Result<Vec<メートル>, 高さ場コンパイルエラー> {
        let (東の点数, 南の点数) = (self.東方向の格子点数()?, self.南方向の格子点数()?);
        let 標本数 = 東の点数
            .checked_mul(南の点数)
            .and_then(|数| usize::try_from(数).ok())
            .ok_or(高さ場コンパイルエラー::格子点数が表現できない)?;
        let mut 高さ一覧 = Vec::with_capacity(標本数);
        for 南の大域添字 in 0..南の点数 {
            for 東の大域添字 in 0..東の点数 {
                高さ一覧.push(self.大域添字の標本を参照する(東の大域添字, 南の大域添字)?);
            }
        }
        Ok(高さ一覧)
    }

    fn 大域添字の標本を参照する(
        &self, 東の大域添字: u32, 南の大域添字: u32
    ) -> Result<メートル, 高さ場コンパイルエラー> {
        let 東 =
            大域の格子添字をチャンクと格子内へ分ける(東の大域添字, self.矩形.最小.x(), self.東方向のチャンク数, self.辺分割数)?;
        let 南 =
            大域の格子添字をチャンクと格子内へ分ける(南の大域添字, self.矩形.最小.z(), self.南方向のチャンク数, self.辺分割数)?;
        let 座標 = チャンク座標::生成する(東.チャンク成分, 南.チャンク成分);
        let 欠け = 高さ場コンパイルエラー::チャンクの矩形に欠けがある {
            東: 座標.x(), 南: 座標.z()
        };
        let 格子 = self.索引.get(&座標).ok_or(欠け)?;
        Ok(メートル::生成する(格子.高さ(東.格子内添字, 南.格子内添字)?))
    }
}

fn チャンク数と辺分割数から格子点数を求める(
    チャンク数: u32, 辺分割数: u32
) -> Result<u32, 高さ場コンパイルエラー> {
    チャンク数
        .checked_mul(辺分割数)
        .and_then(|積| 積.checked_add(1))
        .ok_or(高さ場コンパイルエラー::格子点数が表現できない)
}
