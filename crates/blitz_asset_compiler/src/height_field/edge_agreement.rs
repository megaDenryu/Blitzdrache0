//! 隣り合うチャンクが共有する縁の格子点で、2つの高さ格子が同じ高さを持つことを確かめる工程。
//! 受け取るのはチャンクの矩形と高さ格子の諸元と座標からの索引、返すのは確認の成否である。
//!
//! この検査を置くのは、貼り合わせが重複する縁を片側だけ採るためである。食い違ったまま採ると、採らなかった側の
//! チャンクが焼く地形メッシュと、貼り合わせた高さ場が境界で違う高さを持ち、その境目でキツネが地面から浮くか沈む。
//! 高さ格子はファイルから読むため、同じ大域サンプル添字から引かれたことを型では保証できない。値で確かめる。

use std::collections::HashMap;

use super::chunk_rectangle::チャンクの矩形;
use super::error::高さ場コンパイルエラー;
use crate::height_grid::{高さ格子, 高さ格子諸元};

/// 隣り合う2つのチャンクのどちらの向きで隣り合っているか。縁の格子点の添字の作り方がこの2枝で変わる。
#[derive(Clone, Copy)]
enum 隣り合う向き {
    東,
    南,
}

pub(super) fn 隣り合うチャンクの縁の高さが一致することを確かめる(
    矩形: チャンクの矩形,
    格子の諸元: 高さ格子諸元,
    索引: &HashMap<(i32, i32), &高さ格子>,
) -> Result<(), 高さ場コンパイルエラー> {
    let 辺分割数 = i32::from(格子の諸元.辺分割数());
    for 南 in 矩形.最小.z()..=矩形.最大.z() {
        for 東 in 矩形.最小.x()..=矩形.最大.x() {
            let 格子 = 索引.get(&(東, 南)).ok_or(高さ場コンパイルエラー::チャンクの矩形に欠けがある { 東, 南 })?;
            if let Some(隣) = 索引.get(&(東 + 1, 南)) {
                縁の一列を突き合わせる((東, 南), 格子, 隣, 隣り合う向き::東, 辺分割数)?;
            }
            if let Some(隣) = 索引.get(&(東, 南 + 1)) {
                縁の一列を突き合わせる((東, 南), 格子, 隣, 隣り合う向き::南, 辺分割数)?;
            }
        }
    }
    Ok(())
}

/// 共有する縁の格子点を端から端まで突き合わせる。手前の格子はその向きの上限の添字、隣の格子は0の添字が同じ大域の点を指す。
///
/// 角の4つのチャンクを別に調べないのは、東どうしと南どうしの突き合わせが矩形の全ての隣接で行われ、
/// 角の点が east と south の連鎖で1つの値へ結ばれるためである。
fn 縁の一列を突き合わせる(
    手前の座標: (i32, i32),
    手前の格子: &高さ格子,
    隣の格子: &高さ格子,
    向き: 隣り合う向き,
    辺分割数: i32,
) -> Result<(), 高さ場コンパイルエラー> {
    for 縁に沿う添字 in 0..=辺分割数 {
        let (手前x, 手前z, 隣x, 隣z) = match 向き {
            隣り合う向き::東 => (辺分割数, 縁に沿う添字, 0, 縁に沿う添字),
            隣り合う向き::南 => (縁に沿う添字, 辺分割数, 縁に沿う添字, 0),
        };
        let 高さ = 手前の格子.高さ(手前x, 手前z)?;
        let 隣の高さ = 隣の格子.高さ(隣x, 隣z)?;
        // 同じ大域サンプル添字から引いた標本はビットまで同じになるため、値でなくビット列で比べる。
        // 浮動小数の等価比較では非数どうしが常に食い違いになり、正のゼロと負のゼロが同じ値として通ってしまう。
        if 高さ.to_bits() == 隣の高さ.to_bits() {
            continue;
        }
        let (隣の東, 隣の南) = 隣の座標を求める(手前の座標, 向き);
        return Err(高さ場コンパイルエラー::縁の高さが隣り合うチャンクで食い違う {
            東: 手前の座標.0,
            南: 手前の座標.1,
            隣の東,
            隣の南,
            縁に沿う添字,
            高さ,
            隣の高さ,
        });
    }
    Ok(())
}

fn 隣の座標を求める(手前の座標: (i32, i32), 向き: 隣り合う向き) -> (i32, i32) {
    match 向き {
        隣り合う向き::東 => (手前の座標.0 + 1, 手前の座標.1),
        隣り合う向き::南 => (手前の座標.0, 手前の座標.1 + 1),
    }
}
