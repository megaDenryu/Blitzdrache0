//! 貼り合わせた格子の大域の格子添字を、1つの軸について、それが載るチャンク座標の成分と、そのチャンクの中の
//! 格子添字へ分ける工程。受け取るのは大域の格子添字と矩形の最小の成分とチャンク数と辺分割数、返すのはその2つである。
//!
//! 矩形の東端と南端の格子点は割り算だけでは1つ外のチャンクを指すため、チャンクの差を矩形の中へ寄せてから
//! 余りを求める。隣り合うチャンクが共有する縁は値が等しいため、寄せた側から引いても同じ標本になる。

use super::error::高さ場コンパイルエラー;

/// 1つの軸について、大域の格子添字が指すチャンク座標の成分と、そのチャンクの中の格子添字。
pub(super) struct 軸の分解 {
    pub(super) チャンク成分: i32,
    pub(super) 格子内添字: i32,
}

pub(super) fn 軸を分解する(
    大域添字: u32,
    最小のチャンク成分: i32,
    チャンク数: u32,
    辺分割数: u32,
) -> Result<軸の分解, 高さ場コンパイルエラー> {
    let 表現できない = || 高さ場コンパイルエラー::格子点数が表現できない;
    let 差 = (大域添字 / 辺分割数).min(チャンク数.checked_sub(1).ok_or_else(表現できない)?);
    let 格子内添字 = 大域添字.checked_sub(差 * 辺分割数).ok_or_else(表現できない)?;
    let 差 = i32::try_from(差).map_err(|_| 表現できない())?;
    Ok(軸の分解 {
        チャンク成分: 最小のチャンク成分.checked_add(差).ok_or_else(表現できない)?,
        格子内添字: i32::try_from(格子内添字).map_err(|_| 表現できない())?,
    })
}
