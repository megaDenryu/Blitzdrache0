//! チャンクごとの高さ格子を1枚の高さ場へ貼り合わせる工程の型付きエラー。
//! 貼り合わせの前提(格子が1件以上ある・諸元が揃っている・チャンクが隙間も重複もない矩形をなす)の破れをここで表す。

use blitz_engine::height_field::{高さ場エラー, 高さ場実行時形式エラー};
use thiserror::Error;

#[derive(Debug, Error)]
pub enum 高さ場コンパイルエラー {
    #[error("高さ場へ貼り合わせる高さ格子が1件も無い")]
    高さ格子が1件も無い,
    #[error("チャンク(東{東}、南{南})の高さ格子の諸元が他のチャンクと食い違う")]
    諸元がチャンク間で食い違う { 東: i32, 南: i32 },
    #[error("チャンク(東{東}、南{南})の高さ格子が2件以上ある")]
    チャンク座標が重複している { 東: i32, 南: i32 },
    #[error("チャンクの矩形にチャンク(東{東}、南{南})が欠けている")]
    チャンクの矩形に欠けがある { 東: i32, 南: i32 },
    #[error(
        "チャンク(東{東}、南{南})とチャンク(東{隣の東}、南{隣の南})が共有する縁の{縁に沿う添字}番目の格子点で高さが食い違う({高さ}メートルと{隣の高さ}メートル)"
    )]
    縁の高さが隣り合うチャンクで食い違う {
        東: i32,
        南: i32,
        隣の東: i32,
        隣の南: i32,
        縁に沿う添字: i32,
        高さ: f32,
        隣の高さ: f32,
    },
    #[error("貼り合わせた格子点数がこの形式で表せる範囲を超えた")]
    格子点数が表現できない,
    #[error("高さ格子の読み出しに失敗した: {0}")]
    高さ格子の読み出し失敗(#[from] crate::height_grid::高さ格子エラー),
    #[error("貼り合わせた高さ場が条件を満たさない: {0}")]
    高さ場不正(#[from] 高さ場エラー),
    #[error("高さ場の実行時形式への格納に失敗した: {0}")]
    実行時形式への格納失敗(#[from] 高さ場実行時形式エラー),
}
