//! チャンクごとの高さ格子を1枚の高さ場へ貼り合わせる工程。受け取るのはチャンク座標と高さ格子の組の一覧、
//! 返すのは矩形全体を覆う高さ場である。標本の並べ方は`sample_layout`が持つ。
//!
//! 貼り合わせは重複する縁を片側だけ採り、平均も継ぎ目の補正もしない。片側だけを採ってよい根拠は、
//! 隣り合うチャンクが共有する縁の格子点の値が一致していることであり、その一致はクレート共通の`edge_agreement`が
//! 重なり帯の全体を突き合わせて確かめる。`高さ格子を切り出す`で作った格子は同じ大域サンプル添字から引かれるため
//! これを満たすが、ファイルから読んだ格子は満たす保証が無いため、貼り合わせの前に値で確かめる。
//! 参照: `crates/blitz_asset_compiler/src/height_grid/cutout.rs`

use std::collections::HashMap;

use blitz_engine::height_field::{高さ場, 高さ場諸元};
use blitz_engine::チャンク座標;
use blitz_math::{メートル, 大域メートル};

use super::chunk_rectangle::チャンクの矩形;
use super::error::高さ場コンパイルエラー;
use super::sample_layout::貼り合わせた格子の並び;
use crate::asset_layout::チャンクの高さ格子;
use crate::edge_agreement::隣り合うチャンクの重なり帯が一致することを確かめる;
use crate::height_grid::{高さ格子, 高さ格子諸元};

pub fn チャンクごとの高さ格子から高さ場を組み立てる(
    格子一覧: &[チャンクの高さ格子],
) -> Result<高さ場, 高さ場コンパイルエラー> {
    let 先頭 = 格子一覧.first().ok_or(高さ場コンパイルエラー::高さ格子が1件も無い)?;
    let 格子の諸元 = 先頭.格子().諸元();
    let 座標一覧: Vec<チャンク座標> = 格子一覧.iter().map(チャンクの高さ格子::座標).collect();
    let 矩形 = チャンクの矩形::座標一覧から求める(&座標一覧)?;
    隣り合うチャンクの重なり帯が一致することを確かめる(格子一覧)?;
    let 索引: HashMap<チャンク座標, &高さ格子> = 格子一覧.iter().map(|項目| (項目.座標(), 項目.格子())).collect();
    let 並び = 貼り合わせた格子の並び::生成する(矩形, 格子の諸元, 索引)?;
    let 諸元 = 高さ場の諸元を作る(矩形, 格子の諸元, &並び)?;
    Ok(高さ場::生成する(諸元, 並び.標本を並べる()?)?)
}

/// 格子原点はチャンクの矩形の最小の角の大域ワールド位置であり、チャンク座標と一辺メートルから導く。
/// 格子間隔は高さ格子の刻みメートルをそのまま写す。地形メッシュが張る面と標本の間隔で食い違わせないためである。
fn 高さ場の諸元を作る(
    矩形: チャンクの矩形,
    格子の諸元: 高さ格子諸元,
    並び: &貼り合わせた格子の並び<'_>,
) -> Result<高さ場諸元, 高さ場コンパイルエラー> {
    let 一辺メートル = f64::from(格子の諸元.一辺メートル());
    Ok(高さ場諸元::生成する(
        大域メートル::生成する(f64::from(矩形.最小.x()) * 一辺メートル),
        大域メートル::生成する(f64::from(矩形.最小.z()) * 一辺メートル),
        メートル::生成する(格子の諸元.刻みメートル()),
        並び.東方向の格子点数()?,
        並び.南方向の格子点数()?,
    )?)
}
