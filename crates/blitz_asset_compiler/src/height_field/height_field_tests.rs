//! 貼り合わせの反証。隣り合う格子の重なり帯が一致すること、矩形の欠けを拒むこと、
//! 大域の水平位置での問い合わせが元の格子の標本へ戻ることを確かめる。

#![allow(clippy::unwrap_used)]

use blitz_engine::チャンク座標;
use blitz_math::{大域メートル, 大域ワールド位置};

use super::{チャンクごとの高さ格子から高さ場を組み立てる, 高さ場コンパイルエラー};
use crate::edge_agreement::縁の一致エラー;
use crate::height_grid::{高さ格子, 高さ格子を切り出す, 高さ格子諸元};

/// 1チャンクを4分割し、重なり幅1、一辺100メートルの格子を切り出す。大域サンプル添字から決まる高さは
/// 東と南でそれぞれ重みの違う一次式であり、隣り合うチャンクの縁が同じ値になることを値の並びから判定できる。
fn 検査用の格子を切り出す(チャンク: チャンク座標) -> 高さ格子 {
    let 諸元 = 高さ格子諸元::生成する(4, 1, 100.0).unwrap();
    高さ格子を切り出す(諸元, チャンク, |東, 南| f32::from(東) + f32::from(南) * 10.0).unwrap()
}

fn 二かける二のチャンクの格子一覧() -> Vec<(チャンク座標, 高さ格子)> {
    let mut 一覧 = Vec::new();
    for 南 in 0..2 {
        for 東 in 0..2 {
            let チャンク = チャンク座標::生成する(東, 南);
            一覧.push((チャンク, 検査用の格子を切り出す(チャンク)));
        }
    }
    一覧
}

#[test]
fn 貼り合わせた格子は矩形全体を覆う() {
    let 高さ場 = チャンクごとの高さ格子から高さ場を組み立てる(&二かける二のチャンクの格子一覧()).unwrap();
    let 諸元 = 高さ場.諸元();
    assert_eq!(諸元.東方向の格子点数(), 9);
    assert_eq!(諸元.南方向の格子点数(), 9);
    assert_eq!(諸元.格子原点の東成分(), 大域メートル::生成する(0.0));
    assert_eq!(諸元.格子間隔().値(), 25.0);
}

#[test]
fn 貼り合わせた標本は大域サンプル添字の値をそのまま持つ() {
    let 高さ場 = チャンクごとの高さ格子から高さ場を組み立てる(&二かける二のチャンクの格子一覧()).unwrap();
    // 大域サンプル添字は東西南北とも0から8であり、高さは東 + 南 * 10である。
    assert_eq!(高さ場.格子点の高さ(0, 0).unwrap().値(), 0.0);
    assert_eq!(高さ場.格子点の高さ(4, 0).unwrap().値(), 4.0);
    assert_eq!(高さ場.格子点の高さ(8, 8).unwrap().値(), 88.0);
}

#[test]
fn 大域の水平位置の問い合わせが格子点の標本へ戻る() {
    let 高さ場 = チャンクごとの高さ格子から高さ場を組み立てる(&二かける二のチャンクの格子一覧()).unwrap();
    // 東の格子添字5は東125メートル、南の格子添字3は南75メートルにあたる。
    let 位置 = 大域ワールド位置::生成する(大域メートル::生成する(125.0), 大域メートル::生成する(0.0), 大域メートル::生成する(75.0));
    assert_eq!(高さ場.大域の水平位置から地表高さを求める(位置).unwrap(), 大域メートル::生成する(35.0));
}

#[test]
fn 矩形に欠けのあるチャンク集合を拒む() {
    let mut 一覧 = 二かける二のチャンクの格子一覧();
    一覧.pop();
    let 結果 = チャンクごとの高さ格子から高さ場を組み立てる(&一覧);
    assert!(matches!(結果, Err(高さ場コンパイルエラー::チャンクの矩形に欠けがある { 東: 1, 南: 1 })));
}

/// 東のチャンクだけ高さの式を変えると、重なり帯の格子点で値が食い違う。貼り合わせが片側を無言で採らず、
/// 食い違いをその場で告げることを確かめる。
#[test]
fn 重なり帯の高さが食い違う格子を拒む() {
    let 諸元 = 高さ格子諸元::生成する(4, 1, 100.0).unwrap();
    let mut 一覧 = 二かける二のチャンクの格子一覧();
    一覧[1].1 = 高さ格子を切り出す(諸元, 一覧[1].0, |東, 南| f32::from(東) + f32::from(南) * 10.0 + 1.0).unwrap();
    let 結果 = チャンクごとの高さ格子から高さ場を組み立てる(&一覧);
    assert!(matches!(
        結果,
        Err(高さ場コンパイルエラー::縁が一致しない(
            縁の一致エラー::重なり帯の高さが隣り合うチャンクで食い違う {
                東: 0,
                南: 0,
                隣の東: 1,
                隣の南: 0,
                ..
            }
        ))
    ));
}

#[test]
fn 高さ格子が1件も無い一覧を拒む() {
    let 結果 = チャンクごとの高さ格子から高さ場を組み立てる(&[]);
    assert!(matches!(結果, Err(高さ場コンパイルエラー::高さ格子が1件も無い)));
}
