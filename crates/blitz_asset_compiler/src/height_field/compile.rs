//! 高さ格子のソース一覧から高さ場アセットを焼く局面。受け取るのはチャンクの高さ格子ソースの一覧、
//! 返すのは実行時バイト列とソース依存一覧と容量メタデータである。呼ばれるのは1つの世界につき1回だけである。
//!
//! ソースの読み込み順を引数の並びのままにするのは、読み込んだ順が結果のバイト列へ影響しないためである。
//! 標本の並びはチャンクの矩形から導いた大域の格子添字が決め、同じ入力からは常に同じバイト列を得る。

use std::path::PathBuf;

use blitz_engine::height_field::高さ場を実行時形式へ格納する;
use blitz_engine::アセットメタデータ;

use super::assemble::チャンクごとの高さ格子から高さ場を組み立てる;
use super::error::高さ場コンパイルエラー;
use crate::asset_layout::チャンクの高さ格子ソース;

pub struct コンパイル済み高さ場 {
    pub 実行時バイト列: Vec<u8>,
    pub ソース依存一覧: Vec<PathBuf>,
    pub メタデータ: アセットメタデータ,
}

pub fn 高さ場アセットをコンパイルする(
    チャンクごとのソース一覧: &[チャンクの高さ格子ソース],
) -> Result<コンパイル済み高さ場, 高さ場コンパイルエラー> {
    let mut 格子一覧 = Vec::with_capacity(チャンクごとのソース一覧.len());
    let mut ソース依存一覧 = Vec::with_capacity(チャンクごとのソース一覧.len());
    for ソース in チャンクごとのソース一覧 {
        格子一覧.push(ソース.読み込む()?);
        ソース依存一覧.push(ソース.依存一覧へ載せるパス());
    }
    let 高さ場 = チャンクごとの高さ格子から高さ場を組み立てる(&格子一覧)?;
    Ok(コンパイル済み高さ場 {
        実行時バイト列: 高さ場を実行時形式へ格納する(&高さ場)?,
        ソース依存一覧,
        メタデータ: 高さ場の容量メタデータを作る(),
    })
}

/// 高さ場の容量メタデータ。アセットメタデータが持つ4項目(頂点数・インデックス数・テクスチャ格納バイト数・個体数)は
/// どれもメッシュの物量を表すものであり、高さ場の標本の容量を載せられる項目が1つも無い。項目を新設せず0で登録するのは、
/// 高さ場がチャンク目録に載らずストリーミング予算の見積が1度も読まないためであり、この0は予算の誤りを生まない。
/// 容量メタデータがメッシュを前提にしている点は第2弾(8キロメートル四方級)の設計で扱う。
/// 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断7: 地図の正本を持ち、生成は2系統に分ける」
fn 高さ場の容量メタデータを作る() -> アセットメタデータ {
    アセットメタデータ {
        頂点数: 0,
        インデックス数: 0,
        テクスチャ格納バイト数: 0,
        個体数: 0,
    }
}
