//! 地表材質の重み格子を、地形のUVでそのまま標本できるテクスチャへ写す工程。受け取るのは重みの格子、
//! 返すのはRGBA8で原寸1枚の格納済みテクスチャである。
//!
//! **南北の向きを合わせるのはこの1箇所である。** 重みの格子はZが外側に並び、Zが0の行がチャンクの北端(ワールドの-Z側)である。
//! 一方で地形のUVは v = 1 - z/分割 であり、Vの正の向きがワールドの-Z側を向く。テクセルの行番号は v の増える向きに増えるため、
//! 格子の行をそのままテクスチャの行にすると南北が入れ替わる。ここで行を逆順に並べ、シェーダー側は向きを一切知らない。
//! 半テクセル寄せの標本と合わせて、格子点の添字がちょうどテクセルの中心を指す
//! (参照: `_doc/設計/マルチマテリアルと材質境界.md`「地表の層の重ね合わせ」)。
//!
//! 格納形式をRGBA8に固定するのは、4つの成分が互いに独立に動き、ブロック圧縮のどの分け方にも載らないためである。

use blitz_engine::texture_storage::{テクスチャ格納形式, 格納済みテクスチャ};

use super::weights::{地表材質の重み格子, 地表材質の重み格子エラー};

pub fn 重み格子をテクスチャへ写す(
    格子: &地表材質の重み格子,
) -> Result<格納済みテクスチャ, 地表材質の重み格子エラー> {
    let 一辺 = 格子.諸元().一辺の標本数();
    let mut 画素列 = Vec::with_capacity(格子.諸元().本体のバイト数()?);
    for 行番号 in 0..一辺 {
        let 標本添字z = 一辺 - 1 - 行番号;
        for 標本添字x in 0..一辺 {
            画素列.extend_from_slice(&格子.標本の重み(標本添字x, 標本添字z)?);
        }
    }
    格納済みテクスチャ::生成する(一辺, 一辺, テクスチャ格納形式::RGBA8, vec![画素列])
        .map_err(|誤り| 地表材質の重み格子エラー::テクスチャへ写せない(誤り.to_string()))
}
