//! 地表層テクスチャ集を焼くかどうかと、焼くときの層割当。担当するのは、この2つを1つの値として持ち、
//! 「焼かない世界の層割当」という意味の無い状態を表現できなくすることである。
//!
//! 真偽と層割当を別々に持たないのは、焼くと決めたのに割当を渡し忘れた組が型で通ってしまうためである。

use super::layer_assignment::地表材質の層割当;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 地表層テクスチャ集の焼き方 {
    焼かない, // 検収用の世界と、地形を持たない世界がここへ落ちる
    層割当で焼く(地表材質の層割当),
}

impl 地表層テクスチャ集の焼き方 {
    /// 増分の鍵の見出しへ入れる綴り。焼かない世界と焼く世界を、綴りの上でも区別する。
    pub fn 台帳へ載せる綴り(&self) -> String {
        match self {
            Self::焼かない => "焼かない".to_string(),
            Self::層割当で焼く(層割当) => 層割当.台帳へ載せる綴り(),
        }
    }
}
