//! 地表層テクスチャ集を焼く工程の型付きエラー。層割当の値の破れ・タイル画像の読み取りの破れ・
//! テクスチャ集そのものの検証の破れの3つをこの1つの語彙で表す。

use blitz_engine::surface_layer_textures::{地表層テクスチャ集エラー, 地表層テクスチャ集実行時形式エラー};
use thiserror::Error;

#[derive(Debug, Error)]
pub enum 地表層テクスチャ集コンパイルエラー {
    #[error("地表材質の層{層番号}が参照する材質名が空である")]
    層の材質名が空 { 層番号: usize },
    #[error("材質{材質名}のタイル画像が置き場に無い: {パス}")]
    タイル画像が無い { 材質名: String, パス: String },
    #[error("材質{材質名}のタイル画像の読込に失敗した: {原因}")]
    タイル画像の読込に失敗 { 材質名: String, 原因: String },
    #[error("材質{材質名}のタイル画像の復号に失敗した: {原因}")]
    タイル画像の復号に失敗 { 材質名: String, 原因: String },
    #[error("材質{材質名}のタイル画像を格納済みテクスチャへ焼けない: {原因}")]
    タイル画像を焼けない { 材質名: String, 原因: String },
    #[error("地表層テクスチャ集の組み立てに失敗した: {0}")]
    テクスチャ集不正(#[from] 地表層テクスチャ集エラー),
    #[error("地表層テクスチャ集の実行時形式への格納に失敗した: {0}")]
    実行時形式への格納失敗(#[from] 地表層テクスチャ集実行時形式エラー),
}
