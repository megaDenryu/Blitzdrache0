//! 地表材質の層割当: 4つの層それぞれがどのエンジン材質名を参照するかを持つ値。
//! 焼き方の指定の一部としてコンパイルへ渡り、増分の鍵の綴りにも入る。
//!
//! エディターのマテリアル台帳がこの割当の正本であり、コンパイラは名前の並びだけを受け取る。
//! 台帳そのものを受け取らないのは、識別色のような絵に関わらない欄まで増分の鍵へ入れないためである。

use blitz_engine::surface_layer_textures::地表層の数;

use super::error::地表層テクスチャ集コンパイルエラー;

/// 層割当を指定しない世界が使う材質名。エディターの初期のマテリアル台帳と同じ綴りである。
const 既定の層ごとの材質名: [&str; 地表層の数] = ["grass_a", "dirt_a", "rock_a", "sand_a"];

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 地表材質の層割当 {
    層ごとの材質名: [String; 地表層の数],
}

impl 地表材質の層割当 {
    pub fn 生成する(層ごとの材質名: [String; 地表層の数]) -> Result<Self, 地表層テクスチャ集コンパイルエラー> {
        for (層番号, 材質名) in 層ごとの材質名.iter().enumerate() {
            if 材質名.trim().is_empty() {
                return Err(地表層テクスチャ集コンパイルエラー::層の材質名が空 { 層番号 });
            }
        }
        Ok(Self { 層ごとの材質名 })
    }

    /// エディターのマテリアル台帳を持たない世界が使う割当。検証用のタイル4枚と同じ材質名を指す。
    pub fn 既定を作る() -> Self {
        Self {
            層ごとの材質名: 既定の層ごとの材質名.map(str::to_string),
        }
    }

    pub fn 層ごとの材質名(&self) -> [&str; 地表層の数] {
        [
            self.層ごとの材質名[0].as_str(),
            self.層ごとの材質名[1].as_str(),
            self.層ごとの材質名[2].as_str(),
            self.層ごとの材質名[3].as_str(),
        ]
    }

    /// タイル画像を読む対象の材質名を、重複を除いて並べる。同じ材質名を2つの層が指す割当が正当であるため、
    /// 読む側が同じ画像を2度読まないようここで畳む。
    pub fn 重複を除いた材質名一覧(&self) -> Vec<&str> {
        let mut 一覧: Vec<&str> = Vec::new();
        for 材質名 in self.層ごとの材質名() {
            if !一覧.contains(&材質名) {
                一覧.push(材質名);
            }
        }
        一覧
    }

    /// 増分の鍵の見出しへ入れる綴り。層の並びの順に材質名を連ねる。
    pub fn 台帳へ載せる綴り(&self) -> String {
        self.層ごとの材質名().join(",")
    }
}
