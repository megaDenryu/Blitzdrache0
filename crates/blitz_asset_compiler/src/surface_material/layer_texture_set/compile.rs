//! タイルの置き場と層割当から地表層テクスチャ集アセットを焼く局面。受け取るのは置き場と層割当と格納方針、
//! 返すのは実行時バイト列とソース依存一覧と容量メタデータである。呼ばれるのは1つの世界につき1回だけである。
//!
//! 層が参照する材質名の解決をこの局面の中で行うのは、解決できない割当を実行時形式へ焼かせないためである。
//! 解決の失敗は`地表層テクスチャ集::層が参照する材質名から解決して生成する`が型付きエラーで返す。

use std::path::PathBuf;

use blitz_engine::surface_layer_textures::{
    地表層のタイル, 地表層テクスチャ集, 地表層テクスチャ集を実行時形式へ格納する
};
use blitz_engine::{アセットメタデータ, 高さ場の標本数};

use super::error::地表層テクスチャ集コンパイルエラー;
use super::layer_assignment::地表材質の層割当;
use super::tile_directory::地表層タイルの置き場;
use crate::loader::image_decode::画像のバイト列をrgba8へ復号する;
use crate::texture_storage::{
    テクスチャ格納方針, 方針と役割に従って原寸を格納済みテクスチャへ焼く, 材質テクスチャ役割
};

pub struct コンパイル済み地表層テクスチャ集 {
    pub 実行時バイト列: Vec<u8>,
    pub ソース依存一覧: Vec<PathBuf>,
    pub メタデータ: アセットメタデータ,
}

pub fn 地表層テクスチャ集アセットをコンパイルする(
    置き場: &地表層タイルの置き場,
    層割当: &地表材質の層割当,
    格納方針: テクスチャ格納方針,
) -> Result<コンパイル済み地表層テクスチャ集, 地表層テクスチャ集コンパイルエラー> {
    let 材質名一覧 = 層割当.重複を除いた材質名一覧();
    let mut 材質ごとのタイル = Vec::with_capacity(材質名一覧.len());
    let mut ソース依存一覧 = Vec::with_capacity(材質名一覧.len());
    let mut テクスチャ格納バイト数: u64 = 0;
    for 材質名 in 材質名一覧 {
        let (バイト列, パス) = 置き場.材質のタイル画像を読む(材質名)?;
        let タイル = タイル1枚を焼く(材質名, &バイト列, 格納方針)?;
        for 段 in タイル.ベースカラー().段ごとのバイト列を返す() {
            テクスチャ格納バイト数 = テクスチャ格納バイト数.saturating_add(u64::try_from(段.len()).unwrap_or(u64::MAX));
        }
        材質ごとのタイル.push(タイル);
        ソース依存一覧.push(パス);
    }
    let テクスチャ集 =
        地表層テクスチャ集::層が参照する材質名から解決して生成する(材質ごとのタイル, 層割当.層ごとの材質名())?;
    Ok(コンパイル済み地表層テクスチャ集 {
        実行時バイト列: 地表層テクスチャ集を実行時形式へ格納する(&テクスチャ集)?,
        ソース依存一覧,
        メタデータ: 容量メタデータを作る(テクスチャ格納バイト数),
    })
}

/// タイルの絵は人の目に見える色であるため、格納形式の選択はベースカラーの役割で決める。
fn タイル1枚を焼く(
    材質名: &str,
    バイト列: &[u8],
    格納方針: テクスチャ格納方針,
) -> Result<地表層のタイル, 地表層テクスチャ集コンパイルエラー> {
    let 原寸 = 画像のバイト列をrgba8へ復号する(バイト列).map_err(|原因| {
        地表層テクスチャ集コンパイルエラー::タイル画像の復号に失敗 {
            材質名: 材質名.to_string(),
            原因: 原因.to_string(),
        }
    })?;
    let ベースカラー = 方針と役割に従って原寸を格納済みテクスチャへ焼く(格納方針, 材質テクスチャ役割::ベースカラー, &原寸).map_err(|原因| {
        地表層テクスチャ集コンパイルエラー::タイル画像を焼けない {
            材質名: 材質名.to_string(),
            原因: 原因.to_string(),
        }
    })?;
    Ok(地表層のタイル::生成する(材質名.to_string(), ベースカラー)?)
}

fn 容量メタデータを作る(テクスチャ格納バイト数: u64) -> アセットメタデータ {
    アセットメタデータ {
        頂点数: 0,
        インデックス数: 0,
        テクスチャ格納バイト数,
        個体数: 0,
        高さ場の標本数: 高さ場の標本数::生成する(0),
    }
}
