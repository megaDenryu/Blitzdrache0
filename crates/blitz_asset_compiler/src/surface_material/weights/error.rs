//! 地表材質の重み格子の型付きエラー。諸元の検証・標本の添字・ファイル形式の3つの失敗をこの1つの語彙で表す。

use thiserror::Error;

#[derive(Debug, Error)]
pub enum 地表材質の重み格子エラー {
    #[error("一辺の標本数が2未満である: {0}")]
    一辺の標本数が過少(u32),
    #[error("一辺の標本数が上限{上限}を超えている: {実値}")]
    一辺の標本数が過大 { 実値: u32, 上限: u32 },
    #[error("重みのバイト数が諸元と合わない: 期待{期待}バイト、実際{実際}バイト")]
    バイト数不一致 { 期待: usize, 実際: usize },
    #[error("重みのバイト数をこの処理系のusizeで表せない: 一辺の標本数={一辺の標本数}")]
    バイト数表現不能 { 一辺の標本数: u32 },
    #[error("標本の添字が有効範囲の外である: X={x}、Z={z}")]
    標本添字範囲外 { x: u32, z: u32 },
    #[error("地表材質の重み格子ファイルの読込に失敗した: {0}")]
    ファイル読込失敗(String),
    #[error("地表材質の重み格子のヘッダーが足りない: 実長{実長}バイト")]
    ヘッダー不足 { 実長: usize },
    #[error("地表材質の重み格子の固定識別値が一致しない")]
    固定識別値不一致,
    #[error("未対応の地表材質の重み格子の形式版だった: {0}")]
    未対応形式版(u32),
    #[error("地表材質の層の数が形式の定める{期待}と一致しない: {実際}")]
    層数不一致 { 期待: usize, 実際: usize },
    #[error("地表材質の重み格子の一辺の標本数{重みの一辺}が高さ格子の格子点数{高さの一辺}と一致しない")]
    高さ格子と標本数が食い違う { 重みの一辺: u32, 高さの一辺: u32 },
}
