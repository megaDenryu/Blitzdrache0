//! 地表材質の重み格子のソース形式が、格納と読み込みの往復で標本の並びを保つことの検査。
//!
//! 非対称な標本で確かめるのは、行と列を取り違えた実装が対称な標本では通ってしまうためである。

#![allow(clippy::unwrap_used)]

use super::{
    地表層の数, 地表材質の重み格子, 地表材質の重み格子を格納する, 地表材質の重み格子エラー, 地表材質の重み格子諸元
};

const 一辺: u32 = 3;

/// 標本ごとに違う重みを持つ格子。X方向とZ方向で値の増え方を変えるため、行と列の取り違えが検出できる。
fn 非対称な格子を作る() -> 地表材質の重み格子 {
    let 諸元 = 地表材質の重み格子諸元::生成する(一辺).unwrap();
    let mut 重み一覧 = Vec::new();
    for z in 0..一辺 {
        for x in 0..一辺 {
            let 草 = u8::try_from(x).unwrap();
            let 泥 = u8::try_from(z * 10).unwrap();
            重み一覧.extend_from_slice(&[草, 泥, 7, 9]);
        }
    }
    地表材質の重み格子::生成する(諸元, 重み一覧).unwrap()
}

fn 往復させる(格子: &地表材質の重み格子) -> 地表材質の重み格子 {
    super::read::バイト列から復元する(&地表材質の重み格子を格納する(格子)).unwrap()
}

#[test]
fn 非対称な格子は格納と読み込みの往復で一致する() {
    let 格子 = 非対称な格子を作る();
    assert_eq!(往復させる(&格子), 格子);
}

#[test]
fn 標本の重みはzが外側xが内側の並びで引ける() {
    let 格子 = 往復させる(&非対称な格子を作る());
    assert_eq!(格子.標本の重み(0, 0).unwrap(), [0, 0, 7, 9]);
    assert_eq!(格子.標本の重み(2, 0).unwrap(), [2, 0, 7, 9]);
    assert_eq!(格子.標本の重み(0, 2).unwrap(), [0, 20, 7, 9]);
}

#[test]
fn 範囲の外の標本を引くと型付きエラーになる() {
    let 格子 = 非対称な格子を作る();
    assert!(matches!(格子.標本の重み(一辺, 0), Err(地表材質の重み格子エラー::標本添字範囲外 { .. })));
}

#[test]
fn 塗られていない格子は先頭の層だけが満量である() {
    let 諸元 = 地表材質の重み格子諸元::生成する(一辺).unwrap();
    let 格子 = 地表材質の重み格子::先頭の層だけで塗り潰して生成する(諸元).unwrap();
    assert_eq!(格子.バイト列().len(), 諸元.本体のバイト数().unwrap());
    for z in 0..一辺 {
        for x in 0..一辺 {
            assert_eq!(格子.標本の重み(x, z).unwrap(), [255, 0, 0, 0]);
        }
    }
}

#[test]
fn バイト数が諸元と合わない格子を拒む() {
    let 諸元 = 地表材質の重み格子諸元::生成する(一辺).unwrap();
    assert!(matches!(
        地表材質の重み格子::生成する(諸元, vec![0; 地表層の数]),
        Err(地表材質の重み格子エラー::バイト数不一致 { .. })
    ));
}

#[test]
fn 固定識別値が違うバイト列を拒む() {
    let mut バイト列 = 地表材質の重み格子を格納する(&非対称な格子を作る());
    バイト列[0] = b'X';
    assert!(matches!(
        super::read::バイト列から復元する(&バイト列),
        Err(地表材質の重み格子エラー::固定識別値不一致)
    ));
}

#[test]
fn 高さ格子と標本数が食い違えば拒む() {
    let 格子 = 非対称な格子を作る();
    assert!(格子.高さ格子の格子点数と一致することを確かめる(一辺).is_ok());
    assert!(matches!(
        格子.高さ格子の格子点数と一致することを確かめる(一辺 + 1),
        Err(地表材質の重み格子エラー::高さ格子と標本数が食い違う { .. })
    ));
}
