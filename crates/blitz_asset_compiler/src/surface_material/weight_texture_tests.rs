//! 重み格子からテクスチャへの写しが南北の向きを合わせることの検査。
//!
//! 非対称な標本で確かめるのは、行を逆順にし忘れた実装も、行と列を取り違えた実装も、対称な標本では通ってしまうためである。
//! 期待するテクセルの位置は、地形のUV(v = 1 - z/分割)と半テクセル寄せ(uv' = (uv×(N-1)+0.5)/N)から導く。
//! 格子のZ=0の行はチャンクの北端であり、v=1のときテクスチャの行番号はN-1になる。

#![allow(clippy::unwrap_used)]

use super::weight_texture::重み格子をテクスチャへ写す;
use super::weights::{地表層の数, 地表材質の重み格子, 地表材質の重み格子諸元};

const 一辺: u32 = 3;

/// 北端(Z=0)の行だけを層2(岩)で塗り、それ以外を層0(草)で塗った格子。X方向にも値を変えて列の取り違えを検出する。
fn 北端だけ岩の格子() -> 地表材質の重み格子 {
    let 諸元 = 地表材質の重み格子諸元::生成する(一辺).unwrap();
    let mut 重み一覧 = Vec::new();
    for z in 0..一辺 {
        for x in 0..一辺 {
            let 目印 = u8::try_from(x).unwrap();
            if z == 0 {
                重み一覧.extend_from_slice(&[目印, 0, 255, 0]);
            } else {
                重み一覧.extend_from_slice(&[255, 0, 目印, 0]);
            }
        }
    }
    地表材質の重み格子::生成する(諸元, 重み一覧).unwrap()
}

fn テクセルを引く(画素列: &[u8], 行番号: u32, 列番号: u32) -> [u8; 地表層の数] {
    let 開始 = usize::try_from((行番号 * 一辺 + 列番号) * 4).unwrap();
    画素列[開始..開始 + 地表層の数].try_into().unwrap()
}

#[test]
fn 北端の行はテクスチャの最終行へ写る() {
    let テクスチャ = 重み格子をテクスチャへ写す(&北端だけ岩の格子()).unwrap();
    let 画素列 = &テクスチャ.段ごとのバイト列を返す()[0];
    assert_eq!(テクスチャ.幅を返す(), 一辺);
    assert_eq!(テクスチャ.高さを返す(), 一辺);
    assert_eq!(テクセルを引く(画素列, 一辺 - 1, 0), [0, 0, 255, 0], "最終行は北端の岩である");
    assert_eq!(テクセルを引く(画素列, 0, 0), [255, 0, 0, 0], "先頭行は南側の草である");
}

#[test]
fn 列の並びは格子のx方向のままである() {
    let テクスチャ = 重み格子をテクスチャへ写す(&北端だけ岩の格子()).unwrap();
    let 画素列 = &テクスチャ.段ごとのバイト列を返す()[0];
    assert_eq!(テクセルを引く(画素列, 一辺 - 1, 2), [2, 0, 255, 0], "北端の行のX=2の目印が同じ列へ残る");
    assert_eq!(テクセルを引く(画素列, 0, 2), [255, 0, 2, 0], "南側の行のX=2の目印が同じ列へ残る");
}

#[test]
fn 塗られていない格子は全テクセルが先頭の層だけを満量で持つ() {
    let 諸元 = 地表材質の重み格子諸元::生成する(一辺).unwrap();
    let 格子 = 地表材質の重み格子::先頭の層だけで塗り潰して生成する(諸元).unwrap();
    let テクスチャ = 重み格子をテクスチャへ写す(&格子).unwrap();
    let 画素列 = &テクスチャ.段ごとのバイト列を返す()[0];
    for 行番号 in 0..一辺 {
        for 列番号 in 0..一辺 {
            assert_eq!(テクセルを引く(画素列, 行番号, 列番号), [255, 0, 0, 0]);
        }
    }
}
