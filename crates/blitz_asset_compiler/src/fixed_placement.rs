//! 高さ格子と固定物の原型から、地表へ固定物を据えた地形チャンク1つ分の実行時シーンを焼く。
//! 地面の焼き方は地形の世界の工程をそのまま呼び、この工程が足すのは固定物を地表へ据えることだけである。
//!
//! 固定物をチャンクの側へ焼くのは、据える高さがそのチャンクの高さ格子からしか求まらないためであり、
//! 固定物がその場所のチャンクと一緒に読み込まれて一緒に解除されるためでもある。
//!
//! 群(インスタンス群)でなくこの経路で据えるのは、群の原型が全段で1つのマテリアルを共有する形式契約を持ち、
//! 材質を複数持つ原型を受け取れないためである(参照: `crates/blitz_asset_compiler/src/loader/archetype_material.rs`)。
//! 石積みの小屋のように石と木の2材質を持つ建物は、この経路でしか地面へ載せられない。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「第1段階の定義」の項目10

mod scene;

use blitz_engine::{アセットID, チャンク座標};

use crate::compile::コンパイル済みシーン;
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子を読み込む;
use crate::scene_compiler::ソースアセットのコンパイル係;

/// 固定物1つを、そのチャンクのどこへ据えるかの指定。高さは持たない。据える工程が高さ格子から地表高さを求めるためである。
pub struct 固定物の据え付け {
    pub 原型id: アセットID,
    pub チャンク原点からの東メートル: f32,
    pub チャンク原点からの南メートル: f32,
}

impl ソースアセットのコンパイル係<'_> {
    pub fn 固定物を据えた地形チャンクをコンパイルする(
        &self,
        id: &アセットID,
        所有チャンク: チャンク座標,
        据え付け一覧: &[固定物の据え付け],
    ) -> Result<コンパイル済みシーン, アセットコンパイルエラー> {
        let パス = self.安定idが指すソースのパスを参照する(id)?;
        let 格子 = 高さ格子を読み込む(パス)?;
        let シーン = self.固定物を据えたシーンを組み立てる(&格子, 所有チャンク, パス.to_path_buf(), 据え付け一覧)?;
        コンパイル済みシーン::シーンデータから焼く(シーン)
    }
}
