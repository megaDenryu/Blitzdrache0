//! 地面へ原型を散らす指定の型付きエラー。散布の宣言の値の範囲と、密度場の走査が扱える添字の範囲を、
//! この1つの語彙で表す。
//!
//! アセットコンパイル全体の語彙から分けるのは、散布の宣言を検証する`placement`の外にこれらの失敗を作る場所が
//! 無く、親の語彙へ並べると散布を触らない読み手にも6つの枝が見えるためである。

use thiserror::Error;

#[derive(Debug, Error)]
pub enum 散布コンパイルエラー {
    #[error("散布の走査の列数が受け取れる範囲にない: {0}")]
    走査の列数不正(u8),
    #[error("散布の密度場の升目の標本数が正でない: {0}")]
    密度場の升目が正でない(i16),
    #[error("散布の出現の割合が0以上1以下で下限が上限以下でない: 下限{下限} 上限{上限}")]
    出現割合不正 { 下限: f32, 上限: f32 },
    #[error("散布の大きさの範囲が正で下限が上限以下でない: 下限{下限} 上限{上限}")]
    大きさの範囲不正 { 下限: f32, 上限: f32 },
    #[error("散布の傾きの閾値が有限な非負の値でない: {0}")]
    傾きの閾値不正(f32),
    #[error("散布の大域サンプル添字がi16の範囲を超えた: チャンク成分{チャンク成分}")]
    大域サンプル添字が範囲外 { チャンク成分: i32 },
}
