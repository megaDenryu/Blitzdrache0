//! チャンク目録ソースの形式宣言と一辺の検証だけが返す失敗。

#[derive(Debug, thiserror::Error)]
pub enum チャンク目録コンパイルエラー {
    #[error("チャンク目録ソースの形式宣言が不正である: {0}")]
    形式宣言不正(String),
    #[error("未対応のチャンク目録ソース版だった: {0}")]
    未対応版(String),
    #[error("チャンク目録ソースの一辺が不正である: {0}")]
    チャンク一辺不正(#[from] blitz_engine::チャンク一辺エラー),
}
