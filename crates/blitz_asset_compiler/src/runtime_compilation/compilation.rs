//! 実行時アセットのコンパイル: 1回の実行が焼く1つの世界について、置き場と方針とカタログを保持するサービス型。
//! 焼く工程はこの型のメソッドであり、置き場や実行時カタログを引数で持ち回る自由関数の連鎖にしない。
//!
//! 依存を保持させるのは、ソースルート・出力ルート・世界・焼き方・2つのカタログが、1回のコンパイルの間ずっと
//! 持ち回る状態だからである。引数で渡し歩くと、どの工程がどの状態を触れるかが署名からは分からなくなり、
//! 取り違えても型が通る。工程ごとの中身は、宣言の取り込みが`catalog`、チャンクの取り込みと目録が`chunk_world`、
//! 増分の台帳が`chunk_ledger`、高さ場が`height_field`にあり、保持する依存から下請けの値を組む局面は`wiring`にある。
//! `地表層テクスチャ集`は焼くかどうかに加え、焼く場合は層がどの材質名を参照するかも同じ値が持つ。
//! `種の由来`の1つを、生成台帳の見出しと配置の混合の両方が読む。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

use crate::{
    ソースルート, テクスチャ格納方針, 地表層テクスチャ集の焼き方, 実行時形式の出力ルート, 散布の焼き方, 種の由来, 遠景地形の焼き方
};
use blitz_engine::カタログ;

mod construction;
mod publication;
mod wiring;

use super::bake_report;
use super::placed_instance_tally::置いた個体の勘定;
use super::world::対象世界;
use super::実行時アセットのコンパイルエラー;

pub struct 実行時アセットのコンパイル {
    pub(super) ソースルート: ソースルート,
    pub(super) 出力ルート: 実行時形式の出力ルート,
    pub(super) 世界: 対象世界,
    pub(super) 世界名: String,
    pub(super) 同居植生個体数: usize,
    pub(super) テクスチャ格納方針: テクスチャ格納方針,
    pub(super) 遠景地形: 遠景地形の焼き方, // 世界に1枚だけの遠景地形を焼くか。世界の種別でなくこれが決める
    pub(super) 散布: 散布の焼き方,         // 地面へ散らす原型を焼くか。焼かない側は絵の対照の検収だけ
    pub(super) 地表層テクスチャ集: 地表層テクスチャ集の焼き方, // 地表材質の層に貼るタイルを焼くか
    pub(super) コンパイル時カタログ: カタログ, // ソースの置き場を安定IDから引く。材料を開くのに使う
    pub(super) 実行時カタログ: カタログ,   // 焼き上がりを載せる。出力ルートへ書き出すのはこの1つ
    pub(super) 種の由来: 種の由来,         // この世界が乱数の種から焼かれたものかどうか
}

impl 実行時アセットのコンパイル {
    pub fn 世界を焼く(mut self) -> Result<(), 実行時アセットのコンパイルエラー> {
        let mut 対象一覧 = self
            .アセット宣言をカタログへ写す()
            .map_err(実行時アセットのコンパイルエラー::ソースが不正)?;
        let 取り込み結果 = self
            .チャンク世界を取り込む(&mut 対象一覧)
            .map_err(実行時アセットのコンパイルエラー::ソースが不正)?;
        self.縁の一致を確かめる(&取り込み結果)
            .map_err(実行時アセットのコンパイルエラー::ソースが不正)?;
        let 焼き上がり = self.台帳を見ながら対象一覧を焼く(&対象一覧)?;
        let mut 置いた個体の勘定 = 置いた個体の勘定::零から始める();
        置いた個体の勘定
            .足す(焼き上がり.置いた個体の数)
            .map_err(実行時アセットのコンパイルエラー::ソースが不正)?;
        置いた個体の勘定
            .内訳を取り込む(&焼き上がり.種類ごとの内訳)
            .map_err(実行時アセットのコンパイルエラー::ソースが不正)?;
        // 高さ場アセットは描画対象を1つも持たない高さの表であり、インスタンス群を持ちようがないため勘定へ足さない。
        if self.世界.高さ場を焼くか() {
            self.高さ場を焼いて登録する(&取り込み結果.チャンクごとのソース一覧)?;
        }
        // 層のタイルは世界全体を覆う共有アセットであり、チャンクの数に依らず1枚である。個体を1つも持たないため勘定へ足さない。
        if let 地表層テクスチャ集の焼き方::層割当で焼く(層割当) = self.地表層テクスチャ集.clone() {
            self.地表層テクスチャ集を焼いて登録する(&層割当)?;
        }
        // 遠景を焼くかは世界の種別でなく焼き方の指定が決める。同じ種別の世界が3×3と8km×10kmの2つの規模で焼かれ、
        // 種別で焼くと3×3の遊ぶ世界のカタログにも遠景が入って実行時の大規模世界の判別が誤爆する。
        if self.遠景地形.焼くか() {
            let 遠景が置いた個体の数 = self.遠景地形を焼いて登録する(&取り込み結果.チャンクごとのソース一覧)?;
            置いた個体の勘定
                .足す(遠景が置いた個体の数)
                .map_err(実行時アセットのコンパイルエラー::ソースが不正)?;
        }
        bake_report::焼き上がりの4行を出す(&焼き上がり.勘定, &置いた個体の勘定, &self.実行時カタログ);
        self.出力一式を公開する(&取り込み結果.目録, 焼き上がり.書き出しを待つ生成台帳)
    }
}
