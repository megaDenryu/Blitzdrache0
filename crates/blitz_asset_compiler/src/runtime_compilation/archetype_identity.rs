//! 原型1つを指す識別。担当するのは、安定IDの綴りとソース相対パスの対応を1つの値として持つことだけであり、
//! その原型をどこへどう置くかは知らない。
//!
//! 2つを無名のタプルで持つと、どちらが安定IDでどちらがパスかを添字でしか見分けられず、
//! 取り違えても型が通る。欄を私有にして、綴りが入る口を`生成する`1箇所に閉じる。
//!
//! 安定IDとソース相対パスが常に対で運ばれるのは、同じ1件がアセット定義の一覧(ソースの置き場を決める側)と
//! 群の指定(コンパイラへ渡す側)の両方を生むためである。2つを別の表に分けると、片方だけ足した宣言が
//! カタログ未登録という遠い場所の失敗になる。

use crate::source_asset_paths::ソースアセットの相対パス;

/// 原型1つを指す識別。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 原型の識別 {
    安定id: &'static str,
    ソース相対パス: ソースアセットの相対パス,
}

impl 原型の識別 {
    /// 宣言の表が`const`のまま1行で書けるように`const fn`にする。
    pub(crate) const fn 生成する(安定id: &'static str, ソース相対パス: ソースアセットの相対パス) -> Self {
        Self {
            安定id, ソース相対パス
        }
    }

    pub(crate) const fn 安定id(self) -> &'static str {
        self.安定id
    }

    pub(crate) const fn ソース相対パス(self) -> ソースアセットの相対パス {
        self.ソース相対パス
    }
}
