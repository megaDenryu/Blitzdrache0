//! 生成台帳を見ながらコンパイル対象を焼く工程。受け取るのは対象の一覧、返すのは焼き直しの勘定と確定を待つ台帳であり、
//! 実行時カタログへの登録もここで行う。置き場とカタログと焼き方はコンパイルのサービス型が保持している。
//! 対象1件の仕上げ係とその判定は`one_target`が、焼いて書き出す局面は`bake_one`が、据え置いた対象の項目を前回のカタログから写す手順は
//! `carried_entry`が、材料が同じでも生成物を変える指定は`bake_options`が持つ。
//!
//! 増分の鍵にソース依存の一式を使うのは、チャンク1つが読む材料が1つとは限らないためである。前回の焼き上がりが
//! 何を読んだかは前回のカタログの依存一覧に残っており、その全部が変わっていなければ焼き直す理由が無い。
//!
//! 対象ごとの処理を並列にしてよいのは、1つの対象のコンパイルが他の対象の生成物を1つも読まないためである。
//! 実行時カタログへの登録と台帳への記録は、並列の結果が揃ってから対象の並びの順で行う。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

mod bake_one;
mod bake_options;
mod carried_entry;
mod one_target;

use crate::{焼き直しの勘定, 生成台帳, 生成台帳の見出し, 種類ごとの置いた個体の数, 置いた個体の数};
use rayon::iter::{IntoParallelRefIterator, ParallelIterator};

use super::compilation::実行時アセットのコンパイル;
