pub(super) use bake_options::焼き方の指定;
pub(crate) use one_target::対象1件の仕上げ係;

/// この工程が焼き上げた一式。台帳をここで書き出さずに返すのは、カタログと目録を書き出した後に確定させるためである。
/// 台帳を先に書くと、カタログの書き出しに失敗した実行の後に「新しい台帳と古いカタログ」が残る。次の実行は台帳に従って
/// チャンクを据え置きながら、据え置いた項目を古いカタログから写すため、実行時ファイルとカタログの中身が食い違う。
/// 据え置いた対象は焼く工程を通らないため、`置いた個体の数`へ0体として積み上がり`種類ごとの内訳`へ0体として畳まれる。
pub(super) struct 焼き上がりの一式 {
    pub(super) 勘定: 焼き直しの勘定,
    pub(super) 置いた個体の数: 置いた個体の数,           // 焼いた対象が置いた個体の合計
    pub(super) 種類ごとの内訳: 種類ごとの置いた個体の数, // 焼いた対象が散らした種類ごとの内訳
    pub(super) 書き出しを待つ生成台帳: 生成台帳,
}

/// その対象を増分の台帳で据え置ける単位として扱うかどうか。チャンク世界のチャンクだけが座標で台帳へ記録できる。
/// 世界に1つ据えるアセットは所有チャンクが原点で揃って座標では区別できないため、毎回焼く。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 台帳での扱い {
    チャンクとして記録する,
    毎回焼く,
}

impl 実行時アセットのコンパイル {
    pub(super) fn 台帳を見ながら対象一覧を焼く(
        &mut self,
        対象一覧: &[コンパイル対象],
    ) -> Result<焼き上がりの一式, crate::実行時アセットのコンパイルエラー> {
        let 綴り = self.焼き方の指定を作る().綴りを作る();
        let 見出し = 生成台帳の見出し::実行中の生成器から作る(self.種の由来, &綴り).map_err(crate::実行時アセットのコンパイルエラー::ソースが不正)?;
        self.実行時カタログ
            .世界の由来を記録する(見出し.世界の由来().map_err(crate::実行時アセットのコンパイルエラー::ソースが不正)?);
        let 仕上がり一覧 = self.対象一覧を並列に仕上げる(対象一覧, 見出し)?;
        let mut 今回の台帳 = 生成台帳::見出しを与えて空を作る(見出し);
        let mut 判定一覧 = Vec::with_capacity(仕上がり一覧.len());
        let mut 置いた個体の数 = 置いた個体の数::零();
        let mut 種類ごとの内訳 = 種類ごとの置いた個体の数::空から始める();
        for (対象, 仕上がり) in 対象一覧.iter().zip(仕上がり一覧) {
            置いた個体の数 = 置いた個体の数
                .足す(仕上がり.置いた個体の数)
                .map_err(crate::実行時アセットのコンパイルエラー::ソースが不正)?;
            種類ごとの内訳
                .内訳を取り込む(&仕上がり.種類ごとの内訳)
                .map_err(crate::実行時アセットのコンパイルエラー::ソースが不正)?;
            self.実行時カタログ
                .詳細を登録する(対象.id.clone(), 仕上がり.実行時パス, 仕上がり.ソース依存一覧, 仕上がり.メタデータ);
            if let Some(内容ハッシュ) = 仕上がり.台帳へ記録する内容ハッシュ {
                今回の台帳.内容ハッシュを記録する(対象.所有チャンク, 内容ハッシュ);
            }
            判定一覧.extend(仕上がり.焼き直しの判定);
        }
        Ok(焼き上がりの一式 {
            勘定: 焼き直しの勘定::判定の一覧から数える(判定一覧.into_iter()),
            置いた個体の数,
            種類ごとの内訳,
            書き出しを待つ生成台帳: 今回の台帳,
        })
    }

    /// 対象ごとの仕上がりを並列に作る。台帳とカタログを読むだけの間は`&self`であり、書き込みは呼び出し元が順に行う。
    fn 対象一覧を並列に仕上げる(
        &self,
        対象一覧: &[コンパイル対象],
        見出し: 生成台帳の見出し,
    ) -> Result<Vec<one_target::対象1件の仕上がり>, crate::実行時アセットのコンパイルエラー> {
        let 読み込み = 生成台帳::出力ルートから読み込む(self.出力ルート.台帳の置き場(), 見出し);
        if 読み込み.種または生成器の版が変わったか() {
            self.出力ルート
                .生成物一式を削除する()
                .map_err(crate::実行時アセットのコンパイルエラー::入出力に失敗)?;
        }
        let 前回の台帳 = 読み込み.台帳を受け取る();
        let 前回のカタログ = self.出力ルート.前回の実行時カタログを読む();
        let コンパイル係 = self.ソースアセットのコンパイル係を作る();
        let 仕上げ係 = 対象1件の仕上げ係::生成する(&コンパイル係, &前回の台帳, 前回のカタログ.as_ref());
        対象一覧.par_iter().map(|対象| 仕上げ係.対象1件を仕上げる(対象)).collect()
    }
}
