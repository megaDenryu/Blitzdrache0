//! コンパイル対象のソースが何の形式で書かれているかと、形式ごとに要る付随の宣言。
//! 読み方が形式ごとに違うため判別共用体で持ち、形式を1つ足すときに触る場所をここへ閉じる。
//! 宣言をカタログとコンパイル対象一覧へ写すのは`catalog`が、どの世界が何を宣言するかは`world`が持つ。
//! どの種別の地面が高さ格子で書かれているかの台帳は`ground_grid_ledger`が持つ。

mod ground_grid_ledger;

use crate::配置様式;

use super::archetype_identity::原型の識別;
use super::world::assembled_scatter_declaration::部品で組む散布の宣言;
use super::world::part_row_declaration::部品で組んだ並びの宣言;

/// 地形チャンクへ同居させる植生の宣言。原型を安定IDの綴りで指すのは、`ソース種別`を`Copy`のまま保つためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 同居植生宣言 {
    pub(super) 原型の安定id: &'static str,
    pub(super) 個体数: usize,
}

/// 地面へ置く原型1つ分の宣言。持つのは「どの原型か」と「どう置くか」の2つだけである。
/// 原型を綴りで指すのは、`ソース種別`を`Copy`のまま保つためである。
/// 参照: `crates/blitz_asset_compiler/src/runtime_compilation/archetype_identity.rs`
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 原型と置き方の宣言 {
    pub(super) 原型の識別: 原型の識別,
    pub(super) 配置様式: 配置様式,
}

/// 地面へ固定物を1つ据える宣言。天頂成分を持たないのは、据える高さがその場所の地表高さから決まるためである。
/// 整数のメートルで持つのは、チャンク座標と局所位置への分解を床の除算と剰余で行うためである。
/// 原型を1件ごとに持つのは、据えるものが1種類とは限らず、また1つも据えない世界が原型を宣言しないで済むためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 固定物の据え付け宣言 {
    pub(super) 原型の安定id: &'static str,
    pub(super) 東メートル: i32,
    pub(super) 南メートル: i32,
}

/// コンパイル対象のソースが何の形式で書かれているか。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) enum ソース種別 {
    /// glTF(.gltf/.glb)で書かれたシーン。
    Gltfシーン,
    /// 実寸のメートルで書かれていないglTFシーン。倍率で実寸へ合わせてから焼く。
    寸法を合わせるGltfシーン {
        一様倍率: f32,
    },
    高さ格子 {
        同居植生: Option<同居植生宣言>,
    },
    /// 版付きJSONが高さ格子と編集画面で置いた部品建物を参照する。
    エディターチャンク,
    /// glTFを原型として読み、決定的に生成した配置でインスタンス群を焼く。
    植生 {
        個体数: usize,
    },
    /// 同じ原型から、可視判定の検収用の固定配置と影を受ける床を焼く。
    植生可視判定,
    /// 同じ原型から、恒等でないTRSを与えた個体1体と影を受ける床を焼く。
    植生単一個体,
    /// 同じ原型から、遠方キャスター1体と近距離対照1体と影を受ける床を焼く。影の視距離の切断が消す影を露出する負の対照である。
    植生影視距離,
    /// 段を2つ持つ原型から、カメラの等距離弧へ並べた配置で個体別LODの検収用シーンを焼く。
    植生詳細段,
    /// 高さ格子を地面として焼き、宣言した種の数だけインスタンス群を同居させる。
    見本の集落 {
        群一覧: &'static [原型と置き方の宣言],
    },
    /// 高さ格子を草地の地面として焼き、そのチャンクに載る大域の水平位置へ固定物を据える。
    /// 1つも載らないチャンクは草地の地面だけになり、据え付けを1件も宣言しない世界は地面だけの世界になる。
    /// 群でなくこの種別で据えるのは、群の原型が全段で1つのマテリアルを共有する契約を持ち、材質を複数持つ原型を受け取れないためである。
    /// 散布の一覧が空なら地面と固定物だけになる。散布は世界の規模の絵を作るためのものであり、
    /// 種と密度場から置く置かないを決めるため、宣言は個体数を持たない。
    /// 部品で組む散布の一覧が空なら、地面と固定物と原型の散布だけになる。原型を散らす一覧と分けるのは、
    /// 散らす先が1つの原型でなく部品の一覧と組み立て規則であり、1個体が複数の部品の個体になるためである。
    固定物を据えた高さ格子 {
        据え付け一覧: &'static [固定物の据え付け宣言],
        散布一覧: &'static [原型と置き方の宣言],
        部品で組む散布一覧: &'static [部品で組む散布の宣言],
    },
    /// 高さ格子を平らな地面として焼き、宣言した部品を組み立て規則で件数ぶん展開し、部品の種類ごとの群にまとめる。
    部品で組んだ並び(部品で組んだ並びの宣言),
    /// 高さ格子を庭の地面として焼き、材質見本の立体と遠景地面を据え、宣言した種の数だけインスタンス群を同居させる。
    目視見本 {
        材質見本の立体の安定id: &'static str,
        遠景地面の安定id: &'static str,
        群一覧: &'static [原型と置き方の宣言],
    },
}
