//! コンパイル開始時に指定から依存を揃え、完全な操作サービスを構築する局面。

use blitz_engine::カタログ;

use super::実行時アセットのコンパイル;
use crate::{実行時アセットのコンパイルエラー, 実行時形式の出力ルート, 焼く世界の指定};

impl 実行時アセットのコンパイル {
    pub fn 始める(指定: 焼く世界の指定) -> Result<Self, 実行時アセットのコンパイルエラー> {
        // 種の由来はソースルートを読んで決まるため、置き場を自分のものにする前に取っておく。
        let 種の由来 = 指定
            .世界
            .種の由来を読む(&指定.ソースルート)
            .map_err(実行時アセットのコンパイルエラー::ソースが不正)?;
        Ok(Self {
            ソースルート: 指定.ソースルート,
            出力ルート: 実行時形式の出力ルート::作る(指定.出力ルートのパス).map_err(実行時アセットのコンパイルエラー::入出力に失敗)?,
            世界: 指定.世界,
            世界名: 指定.世界名,
            同居植生個体数: 指定.同居植生個体数,
            テクスチャ格納方針: 指定.テクスチャ格納方針,
            遠景地形: 指定.遠景地形,
            散布: 指定.散布,
            地表層テクスチャ集: 指定.地表層テクスチャ集,
            コンパイル時カタログ: カタログ::空を作る(),
            実行時カタログ: カタログ::空を作る(),
            種の由来,
        })
    }
}
