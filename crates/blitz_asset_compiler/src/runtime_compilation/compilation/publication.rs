//! 焼き上がったカタログ・目録・生成台帳を順に確定し、実行時アセット一式を公開する最終局面。

use blitz_engine::{カタログを実行時形式へ格納する, チャンク目録};

use super::実行時アセットのコンパイル;
use crate::{実行時アセットのコンパイルエラー, 生成台帳};

impl 実行時アセットのコンパイル {
    pub(super) fn 出力一式を公開する(
        &self,
        目録: &チャンク目録,
        生成台帳: 生成台帳,
    ) -> Result<(), 実行時アセットのコンパイルエラー> {
        self.実行時カタログを書き出す()?;
        self.チャンク目録を書き出す(目録)?;
        let 現行id一覧 = self.実行時カタログ.全項目を走査する().map(|(id, _)| id.clone()).collect::<Vec<_>>();
        self.出力ルート
            .現行対象外を削除する(&現行id一覧)
            .map_err(実行時アセットのコンパイルエラー::入出力に失敗)?;
        // 注意: 生成台帳は出力一式の最後に確定させる。先に確定すると、書き出しに失敗した実行が新しい台帳と古いカタログを残す。
        生成台帳
            .出力ルートへ書き出す(self.出力ルート.台帳の置き場())
            .map_err(実行時アセットのコンパイルエラー::入出力に失敗)
    }

    fn 実行時カタログを書き出す(&self) -> Result<(), 実行時アセットのコンパイルエラー> {
        let バイト列 = カタログを実行時形式へ格納する(&self.実行時カタログ).map_err(実行時アセットのコンパイルエラー::ソースが不正)?;
        self.出力ルート
            .実行時カタログを書き出す(&バイト列)
            .map_err(実行時アセットのコンパイルエラー::入出力に失敗)
    }
}
