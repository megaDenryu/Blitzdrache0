//! 実行時アセットのコンパイルが保持する依存から、下請けが要る2つの値を組む局面。担当するのはこの2つだけであり、
//! どちらもフィールドを読むだけで書き換えない。
//!
//! 依存の配線をここへ集めるのは、焼く工程の側が「カタログと格納方針と配置の種の3つをどこから得るか」を
//! 1つも知らずに済むようにするためである。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「判断j」

use crate::{ソースアセットのコンパイル係, 配置の種};

use super::super::chunk_ledger::焼き方の指定;
use super::実行時アセットのコンパイル;

impl 実行時アセットのコンパイル {
    /// 焼く工程が使う係を、自分が保持するコンパイル時カタログと格納方針から組む。ここが依存の配線の1箇所である。
    pub(crate) fn ソースアセットのコンパイル係を作る(&self) -> ソースアセットのコンパイル係<'_> {
        ソースアセットのコンパイル係::生成する(
            &self.コンパイル時カタログ,
            self.テクスチャ格納方針,
            配置の種::種の由来から作る(self.種の由来),
        )
    }

    /// 材料が同じでも生成物を変える指定。増分の鍵の見出しへ入れるため、この型が保持する指定から組む。
    pub(crate) fn 焼き方の指定を作る(&self) -> 焼き方の指定<'_> {
        焼き方の指定 {
            世界名: &self.世界名,
            同居植生個体数: self.同居植生個体数,
            テクスチャ格納方針: self.テクスチャ格納方針,
            遠景地形: self.遠景地形,
            散布一覧: self.散布.適用する(self.世界.散布の宣言一覧()),
        }
    }
}
