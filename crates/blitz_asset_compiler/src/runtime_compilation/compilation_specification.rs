//! 1回の実行で焼く世界と焼き方を、コンパイル開始前に完成させる指定。
//! 完成前の4項目は組み立て器だけが持ち、焼き方を確定した値だけをコンパイルへ渡す。

use std::path::PathBuf;

use crate::{ソースルート, テクスチャ格納方針, 散布の焼き方, 遠景地形の焼き方};

use super::world::対象世界;

pub struct 焼く世界の指定 {
    pub(super) ソースルート: ソースルート,
    pub(super) 出力ルートのパス: PathBuf,
    pub(super) 世界: 対象世界,
    pub(super) 世界名: String,
    pub(super) 同居植生個体数: usize,
    pub(super) テクスチャ格納方針: テクスチャ格納方針,
    pub(super) 遠景地形: 遠景地形の焼き方,
    pub(super) 散布: 散布の焼き方,
}

impl 焼く世界の指定 {
    pub fn エディターの世界を焼く(ソースルート: ソースルート, 出力ルートのパス: PathBuf) -> Self {
        Self::組み立てを始める(
            ソースルート,
            出力ルートのパス,
            対象世界::エディターの世界,
            対象世界::エディターの世界名().to_string(),
        )
        .焼き方を確定する(0, テクスチャ格納方針::全てRGBA8, 遠景地形の焼き方::焼かない, 散布の焼き方::焼かない)
    }

    pub fn 組み立てを始める(
        ソースルート: ソースルート,
        出力ルートのパス: PathBuf,
        世界: 対象世界,
        世界名: String,
    ) -> 焼く世界の指定組み立て器 {
        焼く世界の指定組み立て器 {
            ソースルート,
            出力ルートのパス,
            世界,
            世界名,
        }
    }
}

pub struct 焼く世界の指定組み立て器 {
    ソースルート: ソースルート,
    出力ルートのパス: PathBuf,
    世界: 対象世界,
    世界名: String,
}

impl 焼く世界の指定組み立て器 {
    pub fn 焼き方を確定する(
        self,
        同居植生個体数: usize,
        テクスチャ格納方針: テクスチャ格納方針,
        遠景地形: 遠景地形の焼き方,
        散布: 散布の焼き方,
    ) -> 焼く世界の指定 {
        焼く世界の指定 {
            ソースルート: self.ソースルート,
            出力ルートのパス: self.出力ルートのパス,
            世界: self.世界,
            世界名: self.世界名,
            同居植生個体数,
            テクスチャ格納方針,
            遠景地形,
            散布,
        }
    }
}
