//! 世界ごとに、地表層テクスチャ集を焼くかどうかと焼くときの層割当を引き当てる台帳。
//! ここが持つのは「どの世界がどちらの側か」の対応だけである。
//!
//! 台帳を対象世界の枝の定義から分けるのは、世界が増えるたびにこの一覧だけが伸び、枝の定義と押し合うためである。
//! チャンクのソース形式の台帳を`chunk_source_kind`が、チャンク以外に焼くアセットの一覧を
//! `asset_definition_list`が持つのと同じ分け方である。
//!
//! エディターの世界だけが焼く側にあるのは、地表材質の塗り分けを持つのがエディターの世界だけだからである。
//! 他の世界へも焼かせると、既存の検収の世界のカタログの中身が変わる。

use super::対象世界;
use crate::{地表層テクスチャ集の焼き方, 地表材質の層割当};

/// エディターのマテリアル台帳を持たない入口(コマンド行の`compile-assets`)が使う既定。
/// 台帳を持つ編集サーバーは自分の割当を`焼く世界の指定`へ直接渡すため、この既定を通らない。
pub(super) fn 地表層テクスチャ集の焼き方を選ぶ(世界: 対象世界) -> 地表層テクスチャ集の焼き方 {
    match 世界 {
        対象世界::エディターの世界 | 対象世界::建物一棟の検証世界 => {
            地表層テクスチャ集の焼き方::層割当で焼く(地表材質の層割当::既定を作る())
        }
        対象世界::板の世界
        | 対象世界::地形の世界
        | 対象世界::植生の世界
        | 対象世界::見本の集落の世界
        | 対象世界::部品で組んだ家の並びの世界(_)
        | 対象世界::部品で組んだ一間四方の骨格の並びの世界(_)
        | 対象世界::部品で組んだ木の並びの世界
        | 対象世界::目視見本の世界
        | 対象世界::頂点診断の世界(_)
        | 対象世界::ブロック圧縮の対照世界
        | 対象世界::夜の多光源の世界
        | 対象世界::屋内の多光源の世界
        | 対象世界::場所巡りの世界 => 地表層テクスチャ集の焼き方::焼かない,
    }
}
