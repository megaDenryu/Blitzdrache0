//! 頂点量の診断世界が焼くものの宣言。担当するのは、粗い側と細かい側それぞれについて
//! 「どの原型ソースをどの安定IDで同居植生の素材にするか」を決めることだけである。
//!
//! この2つの世界は地形の代表世界と同じ目録・同じ地面・同じ配置を使い、同居植生の原型のトポロジー量だけが違う。
//! 外形・配置・可視集合が固定されるため、条件間で動く量を投入インデックス数という代理変数で読める。
//! 世界を分ける(代表世界の出力ルートへ焼かない)のは、既存のアセットと検収の判定値を1つも動かさないためである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」

use super::super::catalog::{アセット定義, ソース種別, 同居植生宣言};
use super::asset_declaration::地形世界の起動時シーン;
use super::definition_kind::{ソース専用定義, 必須定義};
use crate::植生診断原型のソース;

/// 診断世界が同居させる原型1件。安定IDとソースの対応をここで結ぶ。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 診断の原型 {
    安定id: &'static str,
    ソース相対パス: &'static str,
}

/// 粗い側。代表世界と同じ原型ソースを読むため、焼き上がりのチャンクは代表世界と一致する。
pub(crate) const 粗い原型: 診断の原型 = 診断の原型 {
    安定id: "vertex_diag_coarse_archetype",
    ソース相対パス: 植生診断原型のソース,
};

/// 細かい側。外形も段の寸法も粗い側と同じで、面を格子へ細分化した原型を読む。
pub(crate) const 細かい原型: 診断の原型 = 診断の原型 {
    安定id: "vertex_diag_fine_archetype",
    ソース相対パス: "vegetation_world/archetype_lod_subdivided.gltf",
};

pub(super) fn 一覧(原型: 診断の原型) -> Vec<アセット定義> {
    vec![
        必須定義(地形世界の起動時シーン.0, 地形世界の起動時シーン.1, ソース種別::Gltfシーン),
        ソース専用定義(原型.安定id, 原型.ソース相対パス),
    ]
}

pub(super) fn 同居植生(原型: 診断の原型, 個体数: usize) -> 同居植生宣言 {
    同居植生宣言 {
        原型の安定id: 原型.安定id,
        個体数,
    }
}
