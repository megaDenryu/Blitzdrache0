//! 部品で組んだ並びの宣言と、その宣言をコンパイラが受け取る指定へ写す工程。担当するのは、どの並びでも変わらない
//! 3つ(部品の一覧・組み上げる件数・どの規則で組むか)を1つの値として持つことである。
//!
//! 家の並びと木の並びが同じ宣言の型を使うのは、焼く工程が完全に同じだからである。地面を平面として焼き、
//! 規則を件数ぶん展開し、部品の種類ごとの群へ畳む。違うのは規則と部品の一覧だけであり、型を2つに分けると
//! 同じ焼き方の写しが2つになる。
//!
//! 規則そのものでなく規則の種類を持つのは、`ソース種別`を`Copy`のまま保つためである。組み立て規則は候補の並びを
//! `Vec`で持つため`Copy`にできない。種類から規則を組む手順は`assembly_rule_choice`が持ち、散布の側と共有する。
//! 参照: `_doc/設計/部品カタログと接合点.md`「部品カタログと展開器」

use crate::{部品で組んだ並びの件数, 部品で組んだ並びの指定};
use blitz_engine::アセットID;

use super::super::archetype_identity::原型の識別;
use super::super::catalog::アセット定義;
use super::assembly_rule_choice::部品の組み立て規則の種類;
use super::definition_kind::外部ソース専用定義;

/// 部品で組んだ並び1つの宣言。何の部品で何件をどの規則で組むかを1つの値で持つ。
/// `ソース種別`を`Copy`のまま保つため、部品を静的な並びで指す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 部品で組んだ並びの宣言 {
    件数: usize,
    規則の種類: 部品の組み立て規則の種類,
}

impl 部品で組んだ並びの宣言 {
    /// 宣言の表が`const`のまま書けるように`const fn`にする。
    pub(super) const fn 生成する(件数: usize, 規則の種類: 部品の組み立て規則の種類) -> Self {
        Self { 件数, 規則の種類 }
    }

    /// この並びが読む部品の一覧。規則の種類が答えるため、宣言は部品を書かない。
    pub(super) fn 部品一覧(self) -> &'static [原型の識別] {
        self.規則の種類.部品一覧()
    }
}

/// 部品の原型のアセット定義一覧。部品は並びが素材として読むだけであり、実行時形式は作らない。
pub(super) fn 部品のアセット定義一覧を作る(部品一覧: &[原型の識別]) -> Vec<アセット定義> {
    部品一覧
        .iter()
        .map(|識別| 外部ソース専用定義(識別.安定id(), 識別.ソース相対パス()))
        .collect()
}

/// 宣言が持つ安定IDの綴りを検証済みのアセットIDへ写し、規則と件数を添えて指定を組む。
pub(crate) fn 部品で組んだ並びの指定を作る(
    宣言: 部品で組んだ並びの宣言
) -> Result<部品で組んだ並びの指定, String> {
    let 安定id一覧 = 宣言
        .部品一覧()
        .iter()
        .map(|識別| アセットID::生成する(識別.安定id()).map_err(|誤り| 誤り.to_string()))
        .collect::<Result<Vec<アセットID>, String>>()?;
    let 件数 = 部品で組んだ並びの件数::生成する(宣言.件数).map_err(|誤り| 誤り.to_string())?;
    let (規則, 種の起点) = 宣言.規則の種類.規則と種の起点を組む()?;
    部品で組んだ並びの指定::生成する(安定id一覧, 規則, 件数, 種の起点).map_err(|誤り| 誤り.to_string())
}
