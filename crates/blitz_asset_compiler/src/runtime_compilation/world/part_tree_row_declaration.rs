//! 部品で組んだ木の並びの世界が焼くものの宣言。担当するのは、カタログへ載せる木の部品3件と、何本並べるかである。
//! 宣言の型と、宣言を指定へ写す手順は`part_row_declaration`が持ち、組み立て規則そのものは同じ場所の`tree_rule`が持つ。
//!
//! **この世界の目的は、部品から組み上がった木の姿を人が近くで見ることである。** 8km世界の散布の固定構図では
//! 1本の木が数画素にしかならず、木に見えるかどうかを絵から判定できない。世界を分けるのは、判定できる大きさで
//! 木を写す構図を持つためである。
//!
//! 4本にするのは、2列2行の正方に並んで隅が欠けないためである。敷地は件数を覆う最小の正方格子へ並べるため、
//! 5本では3列2行になって1つだけ空く。本数を増やしても部品の種類は3のままであり、絵に要る最小で足りる。
//! 参照: `_doc/設計/部品カタログと接合点.md`「段5の到達点」

use super::super::catalog::{アセット定義, ソース種別};
use super::assembly_rule_choice::部品の組み立て規則の種類;
use super::part_row_declaration::{部品で組んだ並びの宣言, 部品のアセット定義一覧を作る};

/// 並べる木の本数。
const 木の本数: usize = 4;

/// この世界がチャンク以外に焼くもの。
pub(super) fn 一覧() -> Vec<アセット定義> {
    部品のアセット定義一覧を作る(部品の組み立て規則の種類::樫の木.部品一覧())
}

pub(super) fn チャンクのソース種別() -> ソース種別 {
    ソース種別::部品で組んだ並び(部品で組んだ並びの宣言::生成する(
        木の本数,
        部品の組み立て規則の種類::樫の木,
    ))
}
