//! 夜の多光源の検収世界が焼くものの宣言。担当するのは、起伏のある地面へ据える遮蔽物2件の原型と据える位置を
//! 1箇所へ集めることだけである。遮蔽物の形と色は`crates/blitz_asset_compiler/examples/generate_source_assets/night_lights_world/obstacle.rs`が持つ。
//!
//! 遮蔽物を2件置くのは、影付きの灯2件が別々の立方体を読んでいることを影の形で反証するためである。
//! 影を落とす灯は中心から近い順に選ばれ、1件目が格子の(列3, 行3)で大域(46.25, 4.0, 46.25)、
//! 2件目が(列4, 行3)で大域(53.75, 4.0, 46.25)に立つ
//! (正本: `crates/blitz_app/src/app/scene_lighting/night_lights/lamp_field.rs`と同`lamp_field/order.rs`)。
//! 遮蔽物はそれぞれの灯からカメラ側(+Z)へ2.75メートル離した位置へ置き、影が灯から見て奥ではなく手前の地面へ伸びるようにする。
//!
//! 注意: 灯の位置が動いたらこの2件の位置も動かさなければならない。灯と遮蔽物が離れると影が影響半径の外へ出て、
//! 影の有無を領域の明るさで読めなくなる。

use super::super::catalog::アセット定義;
use super::super::source_kind::{ソース種別, 固定物の据え付け宣言};
use super::definition_kind::ソース専用定義;
use crate::ソースアセットの相対パス;

/// 影付きの1件目の灯の傍らに立てる、細く高い角柱の原型を指す安定ID。実行時形式は焼かず、地面のチャンクが素材として読むだけである。
const 細く高い角柱: (&str, ソースアセットの相対パス) = (
    "night_lights_tall_pillar",
    ソースアセットの相対パス::生成する("night_lights_world/tall_pillar.gltf"),
);

/// 影付きの2件目の灯の傍らに立てる、幅広く低い壁の原型を指す安定ID。
const 幅広く低い壁: (&str, ソースアセットの相対パス) = (
    "night_lights_wide_wall",
    ソースアセットの相対パス::生成する("night_lights_world/wide_wall.gltf"),
);

/// 遮蔽物を据える大域の水平位置。整数のメートルでしか据えられないため、灯の東西位置(46.25と53.75)を挟む46と54へ置く。
/// 南北は灯の46.25からカメラ側へ2.75メートル離した49である。
const 据える位置の一覧: &[固定物の据え付け宣言] = &[
    固定物の据え付け宣言 {
        原型の安定id: 細く高い角柱.0,
        東メートル: 46,
        南メートル: 49,
    },
    固定物の据え付け宣言 {
        原型の安定id: 幅広く低い壁.0,
        東メートル: 54,
        南メートル: 49,
    },
];

pub(super) fn チャンクのソース種別() -> ソース種別 {
    ソース種別::固定物を据えた高さ格子 {
        据え付け一覧: 据える位置の一覧,
        // 夜の多光源の世界は絵として見る世界でなく検収の世界であるため、地面へ何も散らさない。
        散布一覧: &[],
        部品で組む散布一覧: &[],
    }
}

/// この世界がチャンク以外に焼くもの。どちらの原型もチャンクが素材として読むだけであり、実行時形式は作らない。
pub(super) fn 一覧() -> Vec<アセット定義> {
    vec![
        ソース専用定義(細く高い角柱.0, 細く高い角柱.1),
        ソース専用定義(幅広く低い壁.0, 幅広く低い壁.1),
    ]
}
