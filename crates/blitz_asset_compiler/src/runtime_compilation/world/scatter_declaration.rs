//! 世界ごとに、その世界が地面へ散らす原型の一覧を引き当てる台帳。焼き方の指定がこの綴りを増分の鍵へ入れるため、
//! 宣言を変えた実行は材料が同じでもチャンクを焼き直す。
//!
//! 台帳を親から分けるのは、世界が増えるたびにこの一覧だけが伸び、アセット定義の引き当てと押し合うためである。
//! チャンクのソース形式の台帳を`chunk_source_kind`が持つのと同じ分け方である。
//!
//! 散らさない世界は空の一覧を返す。空を「散らさない」の意味に使えるのは、1件でも宣言があれば散らすからである。

use super::super::source_kind::原型と置き方の宣言;
use super::{fox_tour_declaration, 対象世界};

impl 対象世界 {
    pub(in crate::runtime_compilation) fn 散布の宣言一覧(self) -> &'static [原型と置き方の宣言] {
        match self {
            Self::場所巡りの世界 => fox_tour_declaration::散布の宣言一覧(),
            Self::板の世界
            | Self::地形の世界
            | Self::エディターの世界
            | Self::植生の世界
            | Self::見本の集落の世界
            | Self::部品で組んだ家の並びの世界(_)
            | Self::部品で組んだ木の並びの世界
            | Self::部品で組んだ一間四方の骨格の並びの世界(_)
            | Self::目視見本の世界
            | Self::頂点診断の世界(_)
            | Self::ブロック圧縮の対照世界
            | Self::夜の多光源の世界
            | Self::屋内の多光源の世界 => &[],
        }
    }
}
