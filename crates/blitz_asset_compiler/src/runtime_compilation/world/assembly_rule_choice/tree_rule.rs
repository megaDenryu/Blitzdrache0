//! 樫の木の組み立て規則。幹を3節積んで上へ行くほど細くし、節ごとに枝を1本生やして葉房を付け、幹の頂を冠の葉房で塞ぐ。
//!
//! **細くなる比をどこにも書かない。** 幹頂部の直径0.4へ幹基部の直径0.5を継ぐと接合が0.8を導き、
//! 3節目ではその掛け合わせで0.64になる。規則が持つのは節の数と候補の並びだけであり、太さは部品の宣言が決める。
//!
//! **生え口を3つとも候補に並べる。** 幹の一節は方位が黄金角137.5度ずつ回った生え口を3つ持ち、高さも0.7・1.2・1.7と違う。
//! 節ごとに種で1つ引くため、同じ規則から木ごとに違う枝ぶりが出る。生やさない枝を候補へ混ぜないのは、
//! どの節にも枝がある姿を標準の樫とするためであり、疎らな木を作るときは候補へ`生やさない`を並べる。
//!
//! 冠は幹の最上節の頂部(直径0.4)へ葉房の幹基部の口を継いで載る。これが無いと幹の切り口が絵に出る。
//! 参照: `_doc/設計/部品カタログと接合点.md`「木の実データが導いた倍率」

use blitz_assembly::{
    幹の指定, 幹の節数, 接合点名, 木の規則, 枝の指定, 生成の種, 節ごとの枝の候補, 節の枝, 組み立て規則, 葉房の指定, 部品ID
};

/// 木の並びの展開の種の起点。1件ごとにこの値から番号で分けた種を作る。値を固定するのは、同じ宣言から
/// 同じ配置を得るためである。
const 種の値: u64 = 0x5472_6565_526F_7700;

/// 幹を何節積むか。3節で丈が0から4.88メートルになる(2.0 + 2.0×0.8 + 2.0×0.64)。
const 幹の節数の値: usize = 3;

/// 幹の一節が持つ生え口の名前。節ごとにこの3つから1つを種で引く。
const 生え口の名前一覧: [&str; 3] = ["生え口1", "生え口2", "生え口3"];

pub(super) fn 木の並びの展開の種() -> 生成の種 {
    生成の種::値から生成する(種の値)
}

pub(super) fn 樫の木の規則() -> Result<組み立て規則, String> {
    let 規則 = 木の規則::生成する(
        幹の指定 {
            部品: 識別子("Mod_Tree_Oak_Trunk_Segment")?,
            基部: 名前("幹基部")?,
            頂部: 名前("幹頂部")?,
        },
        幹の節数::生成する(幹の節数の値).map_err(|誤り| 誤り.to_string())?,
        節ごとの枝の候補を組む()?,
        枝の指定 {
            部品: 識別子("Mod_Tree_Oak_Branch_Large")?,
            根元: 名前("枝の根元")?,
            頂芽: 名前("頂芽")?,
        },
        葉房の指定 {
            部品: 識別子("Mod_Tree_Oak_Foliage_Cluster")?,
            枝の先へ付ける根元: 名前("葉房の根元")?,
            幹の頂へ付ける根元: 名前("幹基部")?,
        },
    );
    Ok(組み立て規則::木(規則))
}

fn 節ごとの枝の候補を組む() -> Result<節ごとの枝の候補, String> {
    let mut 候補一覧 = Vec::with_capacity(生え口の名前一覧.len());
    for 綴り in 生え口の名前一覧 {
        候補一覧.push(節の枝::生やす { 生え口: 名前(綴り)? });
    }
    節ごとの枝の候補::生成する(候補一覧).map_err(|誤り| 誤り.to_string())
}

fn 名前(綴り: &str) -> Result<接合点名, String> {
    接合点名::生成する(綴り).map_err(|誤り| 誤り.to_string())
}

fn 識別子(綴り: &str) -> Result<部品ID, String> {
    部品ID::生成する(綴り).map_err(|誤り| 誤り.to_string())
}
