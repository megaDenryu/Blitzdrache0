//! 壁の外面へ何を差し込むかの宣言。飾りを付けない指定と、出窓を必ず差し込む指定と、煙突を必ず立てる指定を持つ。
//!
//! はめ口の材料(`frame_bay_choice`)から分けるのは、取り付く先が違うためである。あちらは骨格の口へ壁を入れる宣言であり、
//! こちらは入った壁の外面へ飾りを差し込む宣言である。**骨格方式で壁が何かを受けるのはこれが初めてであり、
//! 骨格から壁へ、壁から飾りへと2段に伸びる。**
//!
//! 候補を1つに固定するのは、見本の世界の目的が、正解表との突き合わせが通った組み立てそのものを絵にすることだからである。
//! 種で飾りが変わると、絵に写ったものが突き合わせで確かめた組み立てと同じであることを言えなくなる。
//! 参照: `_doc/設計/部品カタログと接合点.md`「壁が外面の取付面を持つ(2026-08-19、Blitzdrache0Assetsの7fc2498)」

use blitz_assembly::{壁の外面の飾り, 壁の外面の飾りの指定, 法線方向のずらし, 飾りの上へ積み足す部品};

use super::frame_bay_choice::{出窓の綴り, 名前, 煙突の綴り, 識別子};

/// 煙突を壁の外面へ立てるときに、1段目の上へ積み足す段数。**この数だけが煙突の高さを決めている。**
/// 屋根の右傾斜面を貫いて上へ出る姿を見るために2段としており、Blender側の正解表も2段である。
const 煙突を上へ積み足す段数: usize = 1;

pub(super) fn 飾りを付けない() -> Result<壁の外面の飾りの指定, String> {
    飾りの指定を組む(vec![壁の外面の飾り::付けない])
}

/// 出窓の差込口は壁の取付面へ寄せずに向かい合う。**零で密着するというBlender側の申告に従っており、
/// 浮きやめり込みが見えたら値を改める。この判断の網は絵の目視だけである。**
/// **出窓は葉であり、上へ積み足すものを1件も持たない。**
pub(super) fn 出窓を必ず差し込む() -> Result<壁の外面の飾りの指定, String> {
    飾りの指定を組む(vec![壁の外面の飾り::差し込む {
        部品: 識別子(出窓の綴り)?,
        差込口: 名前("壁面差込口")?,
        法線方向のずらし: 法線方向のずらし::寄せない(),
        上へ積み足すもの一覧: Vec::new(),
    }])
}

/// 壁の外面へ煙突の1段目を差し込み、その上へ同じ部品を積み足す。**差し込む面0.70×2.60の高さが取付面の
/// 2.60とちょうど等しく、包含はこの等号を収まるものとして通す。** 1段目も積み足す段も寄せずに向かい合う。
pub(super) fn 煙突を必ず立てる() -> Result<壁の外面の飾りの指定, String> {
    飾りの指定を組む(vec![壁の外面の飾り::差し込む {
        部品: 識別子(煙突の綴り)?,
        差込口: 名前("壁面密着面")?,
        法線方向のずらし: 法線方向のずらし::寄せない(),
        上へ積み足すもの一覧: 煙突を積み足す並びを作る()?,
    }])
}

fn 煙突を積み足す並びを作る() -> Result<Vec<飾りの上へ積み足す部品>, String> {
    let mut 並び = Vec::with_capacity(煙突を上へ積み足す段数);
    for _ in 0..煙突を上へ積み足す段数 {
        並び.push(飾りの上へ積み足す部品::生成する(
            名前("上面")?,
            識別子(煙突の綴り)?,
            名前("下面")?,
            法線方向のずらし::寄せない(),
        ));
    }
    Ok(並び)
}

fn 飾りの指定を組む(候補一覧: Vec<壁の外面の飾り>) -> Result<壁の外面の飾りの指定, String> {
    壁の外面の飾りの指定::生成する(名前("外面の飾り取付")?, 候補一覧).map_err(|誤り| 誤り.to_string())
}
