//! 骨格方式の8つの役割へ実データの部品の識別子を預け、ベイ格子の変換が使う文字列を1つ組む工程。
//! 受け取るのは無しであり、返すのは8つの役割が揃った文字列である。
//!
//! 文字列の定数を`frame_bay_choice`から借りるのは、Blender側が部品の名前を改めたときに直す先を1箇所に
//! 保つためである。ここへ文字列を書き写すと、宣言の規則から組んだ家と格子から組んだ家が別の部品を指す。

use blitz_assembly::{部品ID, 骨格方式の役割ごとの部品の識別子, 骨格方式の役割ごとの部品の識別子の組み手, 骨格方式の部品の役割};

use super::frame_bay_choice::{出窓の文字列, 切妻屋根の文字列, 平壁の文字列, 床板の文字列, 扉枠付きの壁の文字列, 煙突の文字列, 窓壁の文字列, 骨格の文字列};

const 役割ごとの部品の識別子: [(骨格方式の部品の役割, &str); 8] = [
    (骨格方式の部品の役割::骨格, 骨格の文字列),
    (骨格方式の部品の役割::平壁, 平壁の文字列),
    (骨格方式の部品の役割::窓壁, 窓壁の文字列),
    (骨格方式の部品の役割::扉枠付きの壁, 扉枠付きの壁の文字列),
    (骨格方式の部品の役割::切妻屋根, 切妻屋根の文字列),
    (骨格方式の部品の役割::床板, 床板の文字列),
    (骨格方式の部品の役割::出窓, 出窓の文字列),
    (骨格方式の部品の役割::煙突セグメント, 煙突の文字列),
];

pub(crate) fn 骨格方式の役割ごとの部品の識別子を組む() -> Result<骨格方式の役割ごとの部品の識別子, String> {
    let mut 組み手 = 骨格方式の役割ごとの部品の識別子の組み手::空から始める();
    for (役割, 文字列) in 役割ごとの部品の識別子 {
        組み手.部品を1つ定める(役割, 部品ID::生成する(文字列).map_err(|誤り| 誤り.to_string())?);
    }
    組み手.部品の識別子を揃えて閉じる().map_err(|誤り| 誤り.to_string())
}
