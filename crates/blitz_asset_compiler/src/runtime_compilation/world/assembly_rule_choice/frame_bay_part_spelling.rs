//! 骨格方式の8つの役割へ実データの部品の識別子を預け、ベイ格子の変換が使う綴りを1つ組む工程。
//! 受け取るのは無しであり、返すのは8つの役割が揃った綴りである。
//!
//! 綴りの定数を`frame_bay_choice`から借りるのは、Blender側が部品の名前を改めたときに直す先を1箇所に
//! 保つためである。ここへ綴りを書き写すと、宣言の規則から組んだ家と格子から組んだ家が別の部品を指す。

use blitz_assembly::{部品ID, 骨格方式の部品の役割, 骨格方式の部品の綴り, 骨格方式の部品の綴りの組み手};

use super::frame_bay_choice::{
    出窓の綴り, 切妻屋根の綴り, 平壁の綴り, 床板の綴り, 扉枠付きの壁の綴り, 煙突の綴り, 窓壁の綴り, 骨格の綴り
};

const 役割ごとの綴り: [(骨格方式の部品の役割, &str); 8] = [
    (骨格方式の部品の役割::骨格, 骨格の綴り),
    (骨格方式の部品の役割::平壁, 平壁の綴り),
    (骨格方式の部品の役割::窓壁, 窓壁の綴り),
    (骨格方式の部品の役割::扉枠付きの壁, 扉枠付きの壁の綴り),
    (骨格方式の部品の役割::切妻屋根, 切妻屋根の綴り),
    (骨格方式の部品の役割::床板, 床板の綴り),
    (骨格方式の部品の役割::出窓, 出窓の綴り),
    (骨格方式の部品の役割::煙突セグメント, 煙突の綴り),
];

pub(crate) fn 骨格方式の部品の綴りを組む() -> Result<骨格方式の部品の綴り, String> {
    let mut 組み手 = 骨格方式の部品の綴りの組み手::空から始める();
    for (役割, 綴り) in 役割ごとの綴り {
        組み手.部品を1つ定める(役割, 部品ID::生成する(綴り).map_err(|誤り| 誤り.to_string())?);
    }
    組み手.綴りを閉じる().map_err(|誤り| 誤り.to_string())
}
