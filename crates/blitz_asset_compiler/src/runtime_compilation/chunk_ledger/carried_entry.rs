//! 前回の実行時カタログを読み、据え置いた対象の項目をそのまま今回の仕上がりへ写す工程。
//!
//! 前回のカタログを材料にするのは、カタログ項目が持つ容量メタデータ(頂点数・インデックス数・テクスチャ格納バイト数・
//! 個体数)を焼き直さずには作れないためである。前回の焼き上がりの項目がそのまま今回の項目であり、写せなければ
//! 据え置く根拠が無いため、その対象は焼き直しへ倒す。

use crate::{チャンクの焼き直し判定, 内容ハッシュ, 種類ごとの置いた個体の数, 置いた個体の数};
use blitz_engine::{カタログ, カタログ項目};

use super::super::compile_target::コンパイル対象;
use super::one_target::対象1件の仕上がり;

pub(super) fn 前回の項目を参照する<'カタログ>(
    対象: &コンパイル対象,
    前回のカタログ: Option<&'カタログ カタログ>,
) -> Option<&'カタログ カタログ項目> {
    前回のカタログ?.項目を参照する(&対象.id)
}

pub(super) fn 前回の項目を写す(
    対象: &コンパイル対象,
    前回のカタログ: Option<&カタログ>,
    内容ハッシュ: 内容ハッシュ,
) -> Result<対象1件の仕上がり, String> {
    let 項目 = 前回の項目を参照する(対象, 前回のカタログ).ok_or_else(|| format!("据え置くと判定した{}の項目が前回のカタログに無い", 対象.id))?;
    println!("[compile_assets] {}: 据え置き", 対象.表示の綴り());
    Ok(対象1件の仕上がり {
        実行時パス: 項目.実行時パス().to_path_buf(),
        ソース依存一覧: 項目.ソース依存一覧().to_vec(),
        メタデータ: 項目.メタデータ(),
        // 据え置いた対象は焼く工程を通らないため、置いた個体を1体も数えない。前回のカタログの個体数を写すと、
        // 焼く側で数えた値でなくなり、実行時カタログとの突き合わせが同じ1つの計算どうしの比べに戻る。
        置いた個体の数: 置いた個体の数::零(),
        // 内訳も同じ理由で空である。据え置いた対象の内訳を前回から写すと、焼く側で数えた値でなくなる。
        種類ごとの内訳: 種類ごとの置いた個体の数::空から始める(),
        台帳へ記録する内容ハッシュ: Some(内容ハッシュ),
        焼き直しの判定: Some(チャンクの焼き直し判定::据え置く { 内容ハッシュ }),
    })
}
