//! 対象1件の仕上げ係と、その据え置きの判定から仕上がりまでの工程。係が保持するのは、対象1件を仕上げるあいだ
//! どの対象でも同じである3つ(コンパイル係・前回の台帳・前回のカタログ)であり、対象ごとに変わるのは引数の対象だけである。
//! 3つを保持させるのは、これらを引数で連ねると同じ3つが焼く工程と判定の工程とコンパイルの割り当てまで4段の署名に並ぶためである。
//! 焼いて書き出す工程は`bake_one`が、ソース種別ごとの割り当ては`compile_target`が、同じ係のメソッドとして持つ。
//! 実行時カタログへの登録をここで行わないのは、この工程を複数のチャンクで同時に走らせるためである。
//! 登録は呼び出し側が対象の並びの順で行い、並列に走らせても結果が同じになるようにする。

use std::path::PathBuf;

use crate::{
    ソースアセットのコンパイル係, チャンクの焼き直し判定, 今回の宣言と依存一式の内容ハッシュを求める, 内容ハッシュ, 生成台帳,
    種類ごとの置いた個体の数, 置いた個体の数,
};
use blitz_engine::{アセットメタデータ, カタログ};

use super::super::compile_target::コンパイル対象;
use super::{carried_entry, 台帳での扱い};

/// 対象1件の仕上がり。実行時カタログの項目3つと、台帳へ記録する内容ハッシュと、勘定へ渡す判定を持つ。
/// 据え置いた対象は焼く工程を通らないため、`置いた個体の数`が0体になり`種類ごとの内訳`が空になる。
/// `台帳へ記録する内容ハッシュ`が値なしなのは台帳が扱わない対象である。世界に1つ据えるアセットは所有チャンクが原点で揃うため、
/// 記録すると原点のチャンクの記録を上書きしてしまう。
pub(super) struct 対象1件の仕上がり {
    pub(super) 実行時パス: PathBuf,
    pub(super) ソース依存一覧: Vec<PathBuf>,
    pub(super) メタデータ: アセットメタデータ,
    pub(super) 置いた個体の数: 置いた個体の数,                   // 焼く工程が実際に置いた個体の数
    pub(super) 種類ごとの内訳: 種類ごとの置いた個体の数,         // 散らした種類ごとの内訳
    pub(super) 台帳へ記録する内容ハッシュ: Option<内容ハッシュ>, // 台帳が扱わない対象では値なし
    pub(super) 焼き直しの判定: Option<チャンクの焼き直し判定>,
}

pub(crate) struct 対象1件の仕上げ係<'借用> {
    pub(crate) コンパイル係: &'借用 ソースアセットのコンパイル係<'借用>,
    前回の台帳: &'借用 生成台帳,
    前回のカタログ: Option<&'借用 カタログ>,
}

impl<'借用> 対象1件の仕上げ係<'借用> {
    pub(super) fn 生成する(
        コンパイル係: &'借用 ソースアセットのコンパイル係<'借用>,
        前回の台帳: &'借用 生成台帳,
        前回のカタログ: Option<&'借用 カタログ>,
    ) -> Self {
        Self {
            コンパイル係,
            前回の台帳,
            前回のカタログ,
        }
    }

    pub(super) fn 対象1件を仕上げる(
        &self,
        対象: &コンパイル対象,
    ) -> Result<対象1件の仕上がり, crate::実行時アセットのコンパイルエラー> {
        let 判定 = self.焼き直しを判定する(対象)?;
        if let Some(チャンクの焼き直し判定::据え置く { 内容ハッシュ }) = 判定 {
            return carried_entry::前回の項目を写す(対象, self.前回のカタログ, 内容ハッシュ);
        }
        let 焼き上がり = self.対象を焼いて書き出す(対象)?;
        Ok(対象1件の仕上がり {
            実行時パス: 焼き上がり.実行時パス,
            ソース依存一覧: 焼き上がり.ソース依存一覧,
            メタデータ: 焼き上がり.メタデータ,
            置いた個体の数: 焼き上がり.置いた個体の数,
            種類ごとの内訳: 焼き上がり.種類ごとの内訳,
            台帳へ記録する内容ハッシュ: 判定.map(|_| 焼き上がり.内容ハッシュ),
            焼き直しの判定: 判定,
        })
    }

    /// 台帳が扱わない対象では値なしを返す。値なしと「焼き直す」を分けるのは、勘定がチャンクの本数だけを数えるためである。
    ///
    /// 鍵へ今回のコンパイル時カタログが対応付けたソースを含めるのは、依存一覧が前回の焼き上がりの記録でしかないためである。
    /// 今回の宣言を見ないと、別のソースルートを指した実行や同じ安定IDの参照先を付け替えた実行が、前回の依存ファイルが
    /// 残っている限り据え置かれ、新しい宣言が無視される。
    fn 焼き直しを判定する(
        &self,
        対象: &コンパイル対象,
    ) -> Result<Option<チャンクの焼き直し判定>, crate::実行時アセットのコンパイルエラー> {
        if 対象.台帳での扱い == 台帳での扱い::毎回焼く {
            return Ok(None);
        }
        let 前回の依存一覧 = carried_entry::前回の項目を参照する(対象, self.前回のカタログ).map(|項目| 項目.ソース依存一覧());
        let 宣言が指すソース = self.コンパイル係.安定idが指すソースのパスを参照する(&対象.id).ok();
        let 今の内容ハッシュ = match (宣言が指すソース, 前回の依存一覧) {
            (Some(宣言が指すソース), Some(依存一覧)) => Some(
                今回の宣言と依存一式の内容ハッシュを求める(宣言が指すソース, 依存一覧)
                    .map_err(crate::実行時アセットのコンパイルエラー::ソースが不正)?,
            ),
            _ => None,
        };
        Ok(Some(self.前回の台帳.チャンクを焼き直すかを判定する(
            対象.所有チャンク,
            今の内容ハッシュ,
            対象.生成物が揃っているか(),
        )))
    }
}
