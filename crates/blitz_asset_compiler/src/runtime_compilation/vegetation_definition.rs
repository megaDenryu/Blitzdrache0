//! 植生定義の正本。エディターのチャンクソースが運ぶ植生定義IDから、焼く実体と個体の大きさの範囲を引く。
//! 建物定義の正本(`building_outline_catalog/definition_source.rs`)と同じ様式であり、未知の識別子は
//! 無言で飛ばさず、引き当ての不在として呼び出し側が型付きの失敗にする。
//!
//! エディターへ配る版付きカタログを持たないのは、段Fの裁定で編集画面が植生の種類を選ばず針葉樹1種に固定であり、
//! 画面が寸法も選択肢も要らないためである。種類を選ばせる時点で建物と同じ外形カタログの口を足す。
//! 参照: `_doc/計画/エディターからゲームまでの統合の作戦.md`「段F」

mod definition_id;

pub use definition_id::植生定義ID;

use super::archetype_identity::原型の識別;
use super::world::assembly_rule_choice::部品の組み立て規則の種類;
use crate::大きさの範囲;

/// 植生1種類の実体。1つのglTFを原型として散らす形と、部品を組み立て規則で組んだものを散らす形の2つに分かれる。
/// 初版の正本は`部品を組み立てて散らす`を持つ定義を1件も置かないため、焼く側はこの枝を受け取ると型付きの失敗を返す。
/// 定義を1件でも足すときは、部品の識別一覧を世界のアセット定義へ載せる工事と、展開器で根を展開する工程を同じ変更で足す。
#[derive(Clone, Copy)]
pub(crate) enum 植生の実体 {
    原型を散らす(原型の識別),
    #[allow(dead_code)]
    部品を組み立てて散らす(部品の組み立て規則の種類), // 樫のように複数の部品から組む木を登録する枝
}

/// 植生定義の正本1件。
#[derive(Clone, Copy)]
pub(crate) struct 植生定義の正本 {
    pub 識別子: &'static str,
    pub 表示名: &'static str,
    pub 実体: 植生の実体,
    pub 大きさの範囲: 大きさの範囲,
}

/// エディターの世界が散らす針葉樹の原型。場所巡りの世界と同じglTFを読むが、安定IDは世界ごとの
/// コンパイル時カタログの鍵であるため別に持つ。
const 針葉樹の原型: 原型の識別 = 原型の識別::生成する("editor_conifer", crate::ソースアセットの相対パス::針葉樹);

/// 若木から成木までの幅。高さ5.6メートルの原型が4.5メートルから9.0メートルの範囲に散る。
/// 場所巡りの世界が同じ原型へ与えている範囲と同じ値を使い、同じ木の背丈が世界ごとに違うことを避ける。
const 針葉樹の大きさの範囲: 大きさの範囲 = 大きさの範囲 { 下限: 0.8, 上限: 1.6 };

pub(crate) fn 全植生定義() -> [植生定義の正本; 1] {
    [植生定義の正本 {
        識別子: "conifer",
        表示名: "針葉樹",
        実体: 植生の実体::原型を散らす(針葉樹の原型),
        大きさの範囲: 針葉樹の大きさの範囲,
    }]
}

pub(crate) fn 識別子から植生定義を参照する(識別子: &植生定義ID) -> Option<植生定義の正本> {
    全植生定義().into_iter().find(|定義| 定義.識別子 == 識別子.綴り())
}

/// 植生定義の正本が読む原型の識別。世界のアセット定義の一覧がこれをそのまま登録する。
/// 部品で組む枝を持つ定義は原型を1つも持たないため、この一覧には現れない。
pub(crate) fn 全植生の原型識別一覧() -> Vec<原型の識別> {
    let mut 一覧: Vec<原型の識別> = Vec::new();
    for 定義 in 全植生定義() {
        if let 植生の実体::原型を散らす(識別) = 定義.実体
            && !一覧.contains(&識別)
        {
            一覧.push(識別);
        }
    }
    一覧
}
