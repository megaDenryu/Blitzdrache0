//! 展開結果からベイ構造を導く工程。受け取るのは配置表と骨格の部品の識別子であり、返すのは横と奥と階の数である。
//!
//! 据わった骨格の平行移動のうち相異なる値の数を軸ごとに数えるだけにするのは、升目の間隔と階高を
//! この工程が知らずに済ませるためである。寸法を持つと、接合点の宣言が変わったときにここも直す羽目になる。
//!
//! 由来が宣言の規則でも格子でも同じ導き方を使う。導き方が2つあると、同じ形の建物が由来ごとに違う
//! ベイ構造を名乗ることが起こる。宣言の側は手で当てた期待値との一致を`acceptance`が確かめる。

use blitz_assembly::{部品ID, 部品ごとの配置表};

use super::super::catalog::ベイ構造;
use super::super::definition_material::建物定義の材料;
use super::super::error::建物外形カタログエラー;

/// 単精度の丸めで同じ位置がわずかにずれるため、この幅までは同じ列とみなす。升目の間隔(2メートル級)に対して
/// 3桁小さく、別の列を同じ列と数え違えることはない。
const 同じ列とみなす許容メートル: f32 = 0.001;

pub(super) fn 据えた骨格からベイ構造を導く(
    材料: &建物定義の材料,
    配置表: &部品ごとの配置表,
    骨格の識別子: &部品ID,
) -> Result<ベイ構造, 建物外形カタログエラー> {
    let 骨格の位置一覧: Vec<[f32; 3]> = 配置表
        .据えた順()
        .iter()
        .filter(|据えた| 据えた.識別子() == 骨格の識別子)
        .map(|据えた| 据えた.配置().平行移動())
        .collect();
    if 骨格の位置一覧.is_empty() {
        return Err(建物外形カタログエラー::骨格が1件も据わらない {
            建物定義: 材料.識別子の綴り().to_string(),
        });
    }
    Ok(ベイ構造 {
        横: 軸の相異なる値を数える(&骨格の位置一覧, 0),
        奥: 軸の相異なる値を数える(&骨格の位置一覧, 2),
        階: 軸の相異なる値を数える(&骨格の位置一覧, 1),
    })
}

/// 名指した軸の値を昇順に並べ、直前の値から許容を超えて離れるたびに1つ数える。
fn 軸の相異なる値を数える(位置一覧: &[[f32; 3]], 軸: usize) -> u32 {
    let mut 値一覧: Vec<f32> = 位置一覧.iter().filter_map(|位置| 位置.get(軸).copied()).collect();
    値一覧.sort_by(|左, 右| 左.total_cmp(右));
    let mut 数 = 0_u32;
    let mut 直前: Option<f32> = None;
    for 値 in 値一覧 {
        if 直前.is_none_or(|前| (値 - 前).abs() > 同じ列とみなす許容メートル) {
            数 = 数.saturating_add(1);
            直前 = Some(値);
        }
    }
    数
}
