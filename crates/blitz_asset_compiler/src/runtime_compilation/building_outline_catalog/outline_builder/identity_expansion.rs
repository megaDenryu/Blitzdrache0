//! 建物1件の組み立てを、原点で回転も拡大もない姿勢のまま展開する工程。受け取るのは部品のソースのパス一覧と
//! 建物定義の材料と格子の台帳であり、返すのは部品ごとの配置表と骨格の部品の識別子である。外形は姿勢に依らない
//! 部品ローカルの形として要るため、ここでは根を恒等の配置に固定する。世界へ据えるときの姿勢は焼き込み側が別に与える。
//!
//! 由来ごとに違うのは手順の作り方だけである。宣言の規則は候補を種から引いて手順を生み、ベイ格子は人が置いた
//! 升目を写して手順を生む。どちらの手順も同じ展開器が同じ規律で展開する。

use std::path::PathBuf;

use blitz_assembly::{展開エラー, 展開器, 部品ID, 部品ごとの配置表, 骨格方式の部品の役割};
use blitz_engine::個体配置;

use super::super::assembly_origin::建物の組み立ての由来;
use super::super::definition_material::建物定義の材料;
use super::super::error::建物外形カタログエラー;
use crate::building_grid_source::建物の格子の台帳;
use crate::loader::部品カタログの読み込み係;
use crate::runtime_compilation::world::assembly_rule_choice::骨格方式の部品の綴りを組む;

pub(super) fn 建物の組み立てを恒等の姿勢で展開する(
    パス一覧: &[PathBuf],
    材料: &建物定義の材料,
    格子の台帳: &建物の格子の台帳,
) -> Result<(部品ごとの配置表, 部品ID), 建物外形カタログエラー> {
    let カタログ = 部品カタログの読み込み係::パスの並びから生成する(パス一覧).組み上げる().map_err(|原因| {
        建物外形カタログエラー::部品カタログを組み立てられない {
            建物定義: 材料.識別子の綴り().to_string(),
            原因: 原因.to_string(),
        }
    })?;
    let 綴り = 骨格方式の部品の綴りを組む().map_err(|原因| 規則を組み立てられない(材料, 原因))?;
    let 骨格の識別子 = 綴り.役割から部品の識別子を引く(骨格方式の部品の役割::骨格).clone();
    let 根 = 個体配置::生成する([0.0; 3], [0.0, 0.0, 0.0, 1.0], [1.0; 3]).map_err(|原因| 展開できない(材料, &原因.to_string()))?;
    let 展開器 = 展開器::カタログを持たせて生成する(カタログ);
    let 展開の結果: Result<部品ごとの配置表, 展開エラー> = match &材料.由来 {
        建物の組み立ての由来::宣言の規則 { 種類, .. } => {
            let (規則, 種) = 種類.規則と種の起点を組む().map_err(|原因| 規則を組み立てられない(材料, 原因))?;
            展開器.規則から展開する(&規則, 種, 根)
        }
        建物の組み立ての由来::ベイ格子 { 格子の識別子 } => {
            let 定義 = 格子の台帳
                .識別子で引く(格子の識別子)
                .ok_or_else(|| 建物外形カタログエラー::格子が台帳に無い {
                    建物定義: 材料.識別子の綴り().to_string(),
                    格子の識別子: 格子の識別子.綴り().to_string(),
                })?;
            展開器.手順を展開する(&定義.格子().組み立て手順へ写す(&綴り), 根)
        }
    };
    let 配置表 = 展開の結果.map_err(|原因| 展開できない(材料, &原因.to_string()))?;
    Ok((配置表, 骨格の識別子))
}

fn 規則を組み立てられない(材料: &建物定義の材料, 原因: String) -> 建物外形カタログエラー {
    建物外形カタログエラー::規則を組み立てられない {
        建物定義: 材料.識別子の綴り().to_string(),
        原因,
    }
}

fn 展開できない(材料: &建物定義の材料, 原因: &str) -> 建物外形カタログエラー {
    建物外形カタログエラー::建物を展開できない {
        建物定義: 材料.識別子の綴り().to_string(),
        原因: 原因.to_string(),
    }
}
