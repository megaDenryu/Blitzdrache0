//! 建物1件の組み立て規則を、原点で回転も拡大もない姿勢のまま展開する工程。受け取るのは部品のソースのパス一覧と
//! 建物定義の正本であり、返すのは部品ごとの配置表である。外形は姿勢に依らない部品ローカルの形として要るため、
//! ここでは根を恒等の配置に固定する。世界へ据えるときの姿勢は焼き込み側が別に与える。

use std::path::PathBuf;

use blitz_assembly::{展開器, 部品ごとの配置表};
use blitz_engine::個体配置;

use super::super::definition_source::建物定義の正本;
use super::super::error::建物外形カタログエラー;
use crate::loader::部品カタログの読み込み係;

pub(super) fn 建物の規則を恒等の姿勢で展開する(
    パス一覧: &[PathBuf],
    正本: &建物定義の正本,
) -> Result<部品ごとの配置表, 建物外形カタログエラー> {
    let カタログ = 部品カタログの読み込み係::パスの並びから生成する(パス一覧).組み上げる().map_err(|原因| {
        建物外形カタログエラー::部品カタログを組み立てられない {
            建物定義: 正本.識別子.to_string(),
            原因: 原因.to_string(),
        }
    })?;
    let (規則, 種) = 正本
        .規則
        .規則と種の起点を組む()
        .map_err(|原因| 建物外形カタログエラー::規則を組み立てられない {
            建物定義: 正本.識別子.to_string(),
            原因,
        })?;
    let 根 = 個体配置::生成する([0.0; 3], [0.0, 0.0, 0.0, 1.0], [1.0; 3]).map_err(|原因| 展開できない(正本, &原因.to_string()))?;
    展開器::カタログを持たせて生成する(カタログ)
        .規則から展開する(&規則, 種, 根)
        .map_err(|原因| 展開できない(正本, &原因.to_string()))
}

fn 展開できない(正本: &建物定義の正本, 原因: &str) -> 建物外形カタログエラー {
    建物外形カタログエラー::建物を展開できない {
        建物定義: 正本.識別子.to_string(),
        原因: 原因.to_string(),
    }
}
