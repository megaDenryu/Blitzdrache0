//! 組み上げた建物定義1件が受理条件を満たすかを確かめる工程。受け取るのは材料・部品の外形一覧・展開した配置表・
//! 求めた外接箱・導いたベイ構造であり、返すのは合否である。
//!
//! この工程が自分で見るのは、外接箱が据えた全部品の写した箱を包んでいることの1つだけである。宣言が手で当てた
//! 期待値との照合(骨格見本の高さとベイ構造)は`declared_expectation`が持つ。触れる材料が違うためであり、
//! こちらは部品の外形と配置表を、あちらは正本の宣言と導いた値だけを見る。

mod declared_expectation;

use blitz_assembly::{群ローカルの箱, 部品ごとの配置表};

use self::declared_expectation::手で当てた期待値との一致を確かめる;
use super::super::catalog::ベイ構造;
use super::super::definition_material::建物定義の材料;
use super::super::error::建物外形カタログエラー;
use super::part_outlines::部品の外形;

/// 単精度の丸めで境界がわずかに外れるため、包含の照合はこの幅まで一致とみなす。
const 許容メートル: f32 = 0.001;

pub(super) fn 受理条件を確かめる(
    材料: &建物定義の材料,
    部品一覧: &[部品の外形],
    配置表: &部品ごとの配置表,
    外接箱: &群ローカルの箱,
    導いたベイ構造: ベイ構造,
) -> Result<(), 建物外形カタログエラー> {
    外接箱が据えた全部品を包むことを確かめる(材料, 部品一覧, 配置表, 外接箱)?;
    手で当てた期待値との一致を確かめる(材料, 外接箱, 導いたベイ構造)
}

fn 外接箱が据えた全部品を包むことを確かめる(
    材料: &建物定義の材料,
    部品一覧: &[部品の外形],
    配置表: &部品ごとの配置表,
    外接箱: &群ローカルの箱,
) -> Result<(), 建物外形カタログエラー> {
    for 据えた in 配置表.据えた順() {
        let 部品 = 部品一覧.iter().find(|部品| &部品.識別子 == 据えた.識別子()).ok_or_else(|| {
            建物外形カタログエラー::据えた部品の外形が無い {
                建物定義: 材料.識別子の綴り().to_string(),
                部品: 据えた.識別子().綴り().to_string(),
            }
        })?;
        let 写した箱 = 部品.境界箱.配置で写す(&据えた.配置());
        if !箱が相手を包むか(外接箱, &写した箱) {
            return Err(建物外形カタログエラー::外接箱が据えた部品を包まない {
                建物定義: 材料.識別子の綴り().to_string(),
                部品: 据えた.識別子().綴り().to_string(),
            });
        }
    }
    Ok(())
}

fn 箱が相手を包むか(外接箱: &群ローカルの箱, 相手: &群ローカルの箱) -> bool {
    (0..3).all(|軸| 外接箱.最小()[軸] <= 相手.最小()[軸] + 許容メートル && 相手.最大()[軸] <= 外接箱.最大()[軸] + 許容メートル)
}
