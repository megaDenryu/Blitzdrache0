//! 組み上げた建物定義1件が受理条件を満たすかを確かめる工程。受け取るのは正本・部品の外形一覧・展開した配置表・
//! 求めた外接箱であり、返すのは合否である。見るのは2つで、外接箱が据えた全部品の写した箱を包んでいることと、
//! 骨格見本2件の高さが階高から手で当てた値と一致することである。
//!
//! 期待する高さは一間四方の骨格が宣言する階高2.60メートルから手で当てた値であり、実装の写しではない。
//! 参照: `_doc/計画/ユビキタス言語.md`「一間四方の骨格」

use blitz_assembly::{群ローカルの箱, 部品ごとの配置表};

use super::super::catalog::建物定義の用途;
use super::super::definition_source::建物定義の正本;
use super::super::error::建物外形カタログエラー;
use super::part_outlines::部品の外形;

/// 階高。一間四方の骨格が上面の接合点を宣言している高さそのものである。
const 階高メートル: f32 = 2.6;

/// 単精度の丸めで境界がわずかに外れるため、包含と高さの照合はこの幅まで一致とみなす。
const 許容メートル: f32 = 0.001;

pub(super) fn 受理条件を確かめる(
    正本: &建物定義の正本,
    部品一覧: &[部品の外形],
    配置表: &部品ごとの配置表,
    外接箱: &群ローカルの箱,
) -> Result<(), 建物外形カタログエラー> {
    外接箱が据えた全部品を包むことを確かめる(正本, 部品一覧, 配置表, 外接箱)?;
    骨格見本の高さが期待と一致することを確かめる(正本, 外接箱)
}

fn 外接箱が据えた全部品を包むことを確かめる(
    正本: &建物定義の正本,
    部品一覧: &[部品の外形],
    配置表: &部品ごとの配置表,
    外接箱: &群ローカルの箱,
) -> Result<(), 建物外形カタログエラー> {
    for 据えた in 配置表.据えた順() {
        let 部品 = 部品一覧.iter().find(|部品| &部品.識別子 == 据えた.識別子()).ok_or_else(|| {
            建物外形カタログエラー::据えた部品の外形が無い {
                建物定義: 正本.識別子.to_string(),
                部品: 据えた.識別子().綴り().to_string(),
            }
        })?;
        let 写した箱 = 部品.境界箱.配置で写す(&据えた.配置());
        if !箱が相手を包むか(外接箱, &写した箱) {
            return Err(建物外形カタログエラー::外接箱が据えた部品を包まない {
                建物定義: 正本.識別子.to_string(),
                部品: 据えた.識別子().綴り().to_string(),
            });
        }
    }
    Ok(())
}

fn 箱が相手を包むか(外接箱: &群ローカルの箱, 相手: &群ローカルの箱) -> bool {
    (0..3).all(|軸| 外接箱.最小()[軸] <= 相手.最小()[軸] + 許容メートル && 相手.最大()[軸] <= 外接箱.最大()[軸] + 許容メートル)
}

fn 骨格見本の高さが期待と一致することを確かめる(
    正本: &建物定義の正本,
    外接箱: &群ローカルの箱,
) -> Result<(), 建物外形カタログエラー> {
    let Some(期待メートル) = 骨格見本の期待する高さ(正本) else {
        return Ok(());
    };
    let 実際メートル = 外接箱.最大()[1] - 外接箱.最小()[1];
    if (実際メートル - 期待メートル).abs() > 許容メートル {
        return Err(建物外形カタログエラー::骨格見本の高さが期待と食い違う {
            建物定義: 正本.識別子.to_string(),
            期待メートル,
            実際メートル,
        });
    }
    Ok(())
}

/// 骨格見本だけが、階高と正本の階数から高さを手で当てられる。壁は骨格の面より上下へ出ないため、
/// 横へ二ベイ継いでも高さは1階ぶん(2.60メートル)のままであり、二段に積むと2階ぶん(5.20メートル)になる。
/// 家屋は屋根が骨格の上面より上へ出るため、この当て方が成り立たず対象にしない。
fn 骨格見本の期待する高さ(正本: &建物定義の正本) -> Option<f32> {
    if 正本.用途 != 建物定義の用途::骨格見本 {
        return None;
    }
    let 階数 = u16::try_from(正本.ベイ.階).ok()?;
    Some(階高メートル * f32::from(階数))
}
