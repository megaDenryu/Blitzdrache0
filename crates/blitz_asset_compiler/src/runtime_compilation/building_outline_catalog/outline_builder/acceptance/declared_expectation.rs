//! 宣言が手で当てた期待値と、展開結果から導いた値の一致を確かめる工程。受け取るのは材料と外接箱と
//! 導いたベイ構造であり、返すのは合否である。見るのは骨格見本の高さと、宣言の規則のベイ構造の2つである。
//!
//! 期待する高さは一間四方の骨格が宣言する階高2.60メートルから手で当てた値であり、実装の写しではない。
//! ベイ構造の一致を見るのは宣言の規則の由来だけである。格子の由来は升目そのものが人の宣言であり、
//! 展開結果から導いた値の外に照らし合わせる正本を持たない。
//! 参照: `_doc/計画/ユビキタス言語.md`「一間四方の骨格」

use blitz_assembly::群ローカルの箱;

use super::super::super::catalog::{ベイ構造, 建物定義の用途};
use super::super::super::definition_material::建物定義の材料;
use super::super::super::error::建物外形カタログエラー;

/// 階高。一間四方の骨格が上面の接合点を宣言している高さそのものである。
const 階高メートル: f32 = 2.6;

/// 単精度の丸めで境界がわずかに外れるため、高さの照合はこの幅まで一致とみなす。
const 許容メートル: f32 = 0.001;

pub(super) fn 手で当てた期待値との一致を確かめる(
    材料: &建物定義の材料,
    外接箱: &群ローカルの箱,
    導いたベイ構造: ベイ構造,
) -> Result<(), 建物外形カタログエラー> {
    骨格見本の高さが期待と一致することを確かめる(材料, 外接箱, 導いたベイ構造)?;
    宣言したベイ構造が導いた値と一致することを確かめる(材料, 導いたベイ構造)
}

/// 骨格見本だけが、階高と階数から高さを手で当てられる。壁は骨格の面より上下へ出ないため、
/// 横へ二ベイ継いでも高さは1階ぶん(2.60メートル)のままであり、二段に積むと2階ぶん(5.20メートル)になる。
/// 家屋は屋根が骨格の上面より上へ出るため、この当て方が成り立たず対象にしない。
fn 骨格見本の高さが期待と一致することを確かめる(
    材料: &建物定義の材料,
    外接箱: &群ローカルの箱,
    導いたベイ構造: ベイ構造,
) -> Result<(), 建物外形カタログエラー> {
    if 材料.用途 != 建物定義の用途::骨格見本 {
        return Ok(());
    }
    let Ok(階数) = u16::try_from(導いたベイ構造.階) else {
        return Ok(());
    };
    let 期待メートル = 階高メートル * f32::from(階数);
    let 実際メートル = 外接箱.最大()[1] - 外接箱.最小()[1];
    if (実際メートル - 期待メートル).abs() > 許容メートル {
        return Err(建物外形カタログエラー::骨格見本の高さが期待と食い違う {
            建物定義: 材料.識別子の綴り().to_string(),
            期待メートル,
            実際メートル,
        });
    }
    Ok(())
}

/// 宣言の規則が手で当てたベイ構造と、展開結果から導いた値の一致を課す。手入力を導出へ寄せた後も、
/// 手で当てた値を検査の期待として残すことで、規則を書き換えたときの形の変化が黙って通らないようにする。
fn 宣言したベイ構造が導いた値と一致することを確かめる(
    材料: &建物定義の材料,
    導いたベイ構造: ベイ構造,
) -> Result<(), 建物外形カタログエラー> {
    let Some(期待) = 材料.由来.期待するベイ構造() else {
        return Ok(());
    };
    if 期待 == 導いたベイ構造 {
        return Ok(());
    }
    Err(建物外形カタログエラー::宣言したベイ構造が導いた値と食い違う {
        建物定義: 材料.識別子の綴り().to_string(),
        期待: ベイ構造の綴りを作る(期待),
        導いた値: ベイ構造の綴りを作る(導いたベイ構造),
    })
}

fn ベイ構造の綴りを作る(構造: ベイ構造) -> String {
    format!("横{}・奥{}・階{}", 構造.横, 構造.奥, 構造.階)
}
