//! 建物1件をどう組み立てるかの由来。宣言の規則から組むか、人が編集したベイ格子から組むかの2系統である。
//!
//! 1段上に判別共用体を立てるのは、カタログの生成・部品の解決・展開の3工程が「どちらの由来か」を同じ形で
//! 場合分けするためである。由来を持たずに規則と格子の2つの表を並べると、片方だけを見て処理する工程が生まれ、
//! 格子から作った建物がカタログに載らないという形の抜けが起きる。
//!
//! ベイ格子の枝が格子の実体でなく識別子を持つのは、格子の正本が編集データの置き場にあり、
//! カタログを組む係が台帳としてまとめて保持するためである(工程が実体を持参して引き回さない)。
//! 参照: `_doc/計画/エディターからゲームまでの統合の作戦.md`「段G」

use super::super::archetype_identity::原型の識別;
use super::super::world::assembly_rule_choice::{部品の組み立て規則の種類, 骨格方式の全部品の一覧};
use super::building_definition_id::建物定義ID;
use super::catalog::ベイ構造;

pub(crate) enum 建物の組み立ての由来 {
    宣言の規則 { // 候補の並びを種から引く。ベイ構造は手で当てた値と展開結果の一致を検査する
        種類: 部品の組み立て規則の種類,
        期待するベイ構造: ベイ構造,
    },
    ベイ格子 { 格子の識別子: 建物定義ID }, // 人が升目を1つずつ置いた格子。ベイ構造は展開結果から導くだけ
}

impl 建物の組み立ての由来 {
    /// この由来が使いうる部品の一覧。格子は8つの役割すべてを人が選べるため、骨格方式の全部品を読む。
    pub(crate) fn 部品一覧(&self) -> &'static [原型の識別] {
        match self {
            Self::宣言の規則 { 種類, .. } => 種類.部品一覧(),
            Self::ベイ格子 { .. } => 骨格方式の全部品の一覧(),
        }
    }

    /// 手で当てたベイ構造の期待値。格子の由来は展開結果だけが答えるため期待値を持たない。
    pub(crate) fn 期待するベイ構造(&self) -> Option<ベイ構造> {
        match self {
            Self::宣言の規則 {
                期待するベイ構造, ..
            } => Some(*期待するベイ構造),
            Self::ベイ格子 { .. } => None,
        }
    }
}
