//! 建物定義1件をカタログへ組み上げるための材料。名乗り(識別子・表示名・用途・入口方向)と由来をまとめて持つ。
//!
//! 宣言の正本(`definition_source`)と格子の台帳という2つの入り口から同じ型を作るのは、以降の工程が
//! どちらの由来かを場合分けせずに走査できるようにするためである。場合分けが残るのは由来の枝の中だけである。

use crate::building_grid_source::格子由来の建物定義;

use super::assembly_origin::建物の組み立ての由来;
use super::building_definition_id::建物定義ID;
use super::catalog::{建物の入口方向, 建物定義の用途};
use super::definition_source::建物定義の正本;
use super::error::建物外形カタログエラー;

pub(crate) struct 建物定義の材料 {
    pub(crate) 識別子: 建物定義ID,
    pub(crate) 表示名: String,
    pub(crate) 用途: 建物定義の用途,
    pub(crate) 入口のローカル方向: 建物の入口方向,
    pub(crate) 由来: 建物の組み立ての由来,
}

impl 建物定義の材料 {
    pub(crate) fn 宣言の正本から生成する(正本: 建物定義の正本) -> Result<Self, 建物外形カタログエラー> {
        Ok(Self {
            識別子: 建物定義ID::生成する(正本.識別子).map_err(|原因| 建物外形カタログエラー::規則を組み立てられない {
                建物定義: 正本.識別子.to_string(),
                原因,
            })?,
            表示名: 正本.表示名.to_string(),
            用途: 正本.用途,
            入口のローカル方向: 正本.入口のローカル方向,
            由来: 建物の組み立ての由来::宣言の規則 {
                種類: 正本.規則,
                期待するベイ構造: 正本.ベイ,
            },
        })
    }

    /// 格子から組んだ建物はすべて家屋である。骨格見本は部品の噛み合いを見せるための宣言の見本であり、
    /// 人が升目を置いて作るものではない。
    pub(crate) fn 格子由来の定義から生成する(定義: &格子由来の建物定義) -> Self {
        Self {
            識別子: 定義.識別子().clone(),
            表示名: 定義.表示名().to_string(),
            用途: 建物定義の用途::家屋,
            入口のローカル方向: 定義.入口のローカル方向(),
            由来: 建物の組み立ての由来::ベイ格子 {
                格子の識別子: 定義.識別子().clone(),
            },
        }
    }

    pub(crate) fn 識別子の綴り(&self) -> &str {
        self.識別子.綴り()
    }
}
