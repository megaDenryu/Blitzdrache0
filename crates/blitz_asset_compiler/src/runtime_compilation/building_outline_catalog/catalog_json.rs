//! 建物外形カタログを、編集サーバーと画面が読む版付きJSONへ写す境界。

use serde_json::{Value, json};

use super::catalog::{建物外形カタログ, 建物定義, 建物定義の用途};
use super::error::建物外形カタログエラー;

pub(super) fn 整形済みのバイト列を作る(カタログ: &建物外形カタログ) -> Result<Vec<u8>, 建物外形カタログエラー> {
    let 値 = json!({
        "形式版": カタログ.形式版,
        "建物定義一覧": カタログ.建物定義一覧.iter().map(建物定義を値へ写す).collect::<Vec<_>>(),
    });
    let mut バイト列 = serde_json::to_vec_pretty(&値)?;
    バイト列.push(b'\n');
    Ok(バイト列)
}

fn 建物定義を値へ写す(定義: &建物定義) -> Value {
    json!({
        "識別子": 定義.識別子,
        "表示名": 定義.表示名,
        "用途": 用途の綴り(定義.用途),
        "部品の識別子一覧": 定義.部品の識別子一覧,
        "ベイ": { "横": 定義.ベイ.横, "奥": 定義.ベイ.奥, "階": 定義.ベイ.階 },
        "高さメートル": 定義.高さメートル,
        "入口のローカル方向": { "x": 定義.入口のローカル方向.x, "z": 定義.入口のローカル方向.z },
        "外接箱": { "最小": 定義.外接箱.最小, "最大": 定義.外接箱.最大 },
    })
}

fn 用途の綴り(用途: 建物定義の用途) -> &'static str {
    match 用途 {
        建物定義の用途::骨格見本 => "骨格見本",
        建物定義の用途::家屋 => "家屋",
    }
}
