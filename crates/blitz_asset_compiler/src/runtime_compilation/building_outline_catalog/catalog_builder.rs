//! 建物外形カタログの組み立て係: 建物の格子の台帳を保持し、宣言の規則5件と格子由来の建物を1つのカタログへ
//! 組み上げる操作サービス。
//!
//! 台帳を保持するのは、組み立てのたびに置き場を読み直さないためであり、編集サーバーが「この1件を差し替えたら
//! 組み立てが通るか」を正本を書き換える前に確かめられるようにするためである。台帳を引数で持参させる形にすると、
//! 保存の検査と起動時の生成で別の台帳を渡しても型が通る。
//! 参照: `_doc/計画/エディターからゲームまでの統合の作戦.md`「段G」

use super::catalog::建物外形カタログ;
use super::error::建物外形カタログエラー;
use super::outline_builder;
use super::replacement_candidate::差し替えの候補;
use crate::building_grid_source::{台帳に載る建物, 建物の格子の台帳, 建物の格子の置き場};

pub struct 建物外形カタログの組み立て係 {
    格子の台帳: 建物の格子の台帳,
}

impl 建物外形カタログの組み立て係 {
    pub fn 台帳を持たせて生成する(格子の台帳: 建物の格子の台帳) -> Self {
        Self { 格子の台帳 }
    }

    /// 置き場の全建物を解いてから係を作る。格子が1件も無いプロジェクトは台帳0件で成立する。
    pub fn 置き場から台帳を読んで生成する(置き場: &建物の格子の置き場) -> Result<Self, 建物外形カタログエラー> {
        Ok(Self::台帳を持たせて生成する(建物の格子の台帳::置き場から読む(置き場)?))
    }

    pub fn 組み立てる(&self) -> Result<建物外形カタログ, 建物外形カタログエラー> {
        outline_builder::建物外形カタログを実体から組み立てる(&self.格子の台帳)
    }

    /// 名指した1件を差し替えた台帳でカタログを組み直し、通った結果を候補として返す。自分の台帳はまだ変えない。
    /// 保存の検査がこの口を使い、通らない格子で正本を書き換えないようにする。
    pub fn 建物を1件差し替えた組み直しを試す(
        &self,
        建物: 台帳に載る建物,
    ) -> Result<差し替えの候補, 建物外形カタログエラー> {
        let mut 試す台帳 = self.格子の台帳.clone();
        試す台帳.建物を1件預ける(建物);
        let カタログ = outline_builder::建物外形カタログを実体から組み立てる(&試す台帳)?;
        Ok(差し替えの候補::組み上がった材料から生成する(試す台帳, カタログ))
    }

    /// 候補の台帳を自分のものにする。正本の2つのファイルを書き終えてから呼ぶ。
    pub fn 候補を台帳へ取り込む(&mut self, 候補: 差し替えの候補) {
        self.格子の台帳 = 候補.台帳を取り出す();
    }

    pub fn 格子の台帳(&self) -> &建物の格子の台帳 {
        &self.格子の台帳
    }
}
