//! 建物外形カタログの材料解決・展開・書き出しで起きる失敗。

#[derive(Debug, thiserror::Error)]
pub enum 建物外形カタログエラー {
    #[error("建物定義{建物定義}の部品ソースを参照できない: {原因}")]
    部品ソースを参照できない { 建物定義: String, 原因: String },
    #[error("建物定義{建物定義}の部品カタログを組み立てられない: {原因}")]
    部品カタログを組み立てられない { 建物定義: String, 原因: String },
    #[error("建物定義{建物定義}の規則を組み立てられない: {原因}")]
    規則を組み立てられない { 建物定義: String, 原因: String },
    #[error("建物定義{建物定義}を展開できない: {原因}")]
    建物を展開できない { 建物定義: String, 原因: String },
    #[error("建物定義{建物定義}が据えた部品{部品}の外形を参照できない")]
    据えた部品の外形が無い { 建物定義: String, 部品: String },
    #[error("建物定義{建物定義}は部品を1件も据えなかった")]
    建物が空 { 建物定義: String },
    #[error("建物外形カタログのJSONを組み立てられない: {0}")]
    Jsonを組み立てられない(#[from] serde_json::Error),
    #[error("建物外形カタログを{パス}へ書き込めない: {原因}")]
    ファイルを書き込めない { パス: String, 原因: std::io::Error },
}
