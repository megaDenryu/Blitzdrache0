//! 差し替えの候補: 建物1件を差し替えた台帳と、その台帳で組み上がったカタログの組。
//!
//! 組み直しの結果を候補として一度返すのは、記憶の台帳への確定を正本のファイルを書き終えたあとへ遅らせるためである。
//! 組み直しと同時に台帳を書き換えると、そのあとのファイル書き込みが落ちたときに、ディスクに無い格子が記憶の台帳へ
//! 残り、以後の組み直しと書き出しが正本と食い違う。
//! 参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断2」

use super::catalog::建物外形カタログ;
use crate::building_grid_source::建物の格子の台帳;

#[must_use]
pub struct 差し替えの候補 {
    台帳: 建物の格子の台帳,
    カタログ: 建物外形カタログ,
}

impl 差し替えの候補 {
    pub(super) fn 組み上がった材料から生成する(台帳: 建物の格子の台帳, カタログ: 建物外形カタログ) -> Self {
        Self { 台帳, カタログ }
    }

    /// 組み上がったカタログ。正本のファイルへ書くのはこの値である。
    pub fn カタログ(&self) -> &建物外形カタログ {
        &self.カタログ
    }

    pub(super) fn 台帳を取り出す(self) -> 建物の格子の台帳 {
        self.台帳
    }
}
