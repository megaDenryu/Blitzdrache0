use blitz_assembly::部品ごとの配置表;

use self::acceptance::受理条件を確かめる;
use self::bay_structure::据えた骨格からベイ構造を導く;
use self::combined_box::建物全体の箱を作る;
use self::identity_expansion::建物の組み立てを恒等の姿勢で展開する;
use self::part_outlines::{部品のパス一覧を参照する, 部品の外形一覧を読む};
use super::catalog::{建物の外接箱, 建物外形カタログ, 建物定義};
use super::definition_material::建物定義の材料;
use super::definition_source::全定義;
use super::error::建物外形カタログエラー;
use crate::building_grid_source::建物の格子の台帳;
use crate::runtime_compilation::source_location::外部ソースルート;

pub(super) fn 建物外形カタログを実体から組み立てる(
    格子の台帳: &建物の格子の台帳,
) -> Result<建物外形カタログ, 建物外形カタログエラー> {
    let 外部ルート = 外部ソースルート::解決する();
    if let 外部ソースルート::不在 { 診断 } = &外部ルート {
        return Err(建物外形カタログエラー::外部ソースルート不在(診断.clone()));
    }
    let mut 定義一覧 = Vec::with_capacity(全定義().len() + 格子の台帳.件数());
    for 材料 in 材料一覧を並べる(格子の台帳)? {
        定義一覧.push(建物定義を実体から組み立てる(&外部ルート, &材料, 格子の台帳)?);
    }
    Ok(建物外形カタログ::定義一覧から生成する(定義一覧))
}

/// 宣言の規則の5件を先に、格子から解けた建物を識別子の昇順で後に並べる。並びを固定するのは、
/// 同じ入力からは常に同じカタログのバイト列が出ることを守るためである。
fn 材料一覧を並べる(格子の台帳: &建物の格子の台帳) -> Result<Vec<建物定義の材料>, 建物外形カタログエラー> {
    let mut 一覧 = Vec::with_capacity(全定義().len() + 格子の台帳.件数());
    for 正本 in 全定義() {
        一覧.push(建物定義の材料::宣言の正本から生成する(正本)?);
    }
    一覧.extend(格子の台帳.昇順に数え上げる().map(建物定義の材料::格子由来の定義から生成する));
    Ok(一覧)
}

fn 建物定義を実体から組み立てる(
    外部ルート: &外部ソースルート,
    材料: &建物定義の材料,
    格子の台帳: &建物の格子の台帳,
) -> Result<建物定義, 建物外形カタログエラー> {
    let パス一覧 = 部品のパス一覧を参照する(外部ルート, 材料)?;
    let 部品一覧 = 部品の外形一覧を読む(&パス一覧, 材料)?;
    let (配置表, 骨格の識別子) = 建物の組み立てを恒等の姿勢で展開する(&パス一覧, 材料, 格子の台帳)?;
    let 箱 = 建物全体の箱を作る(材料, &部品一覧, &配置表)?;
    let ベイ = 据えた骨格からベイ構造を導く(材料, &配置表, &骨格の識別子)?;
    受理条件を確かめる(材料, &部品一覧, &配置表, &箱, ベイ)?;
    Ok(建物定義 {
        識別子: 材料.識別子.clone(),
        表示名: 材料.表示名.clone(),
        用途: 材料.用途,
        部品の識別子一覧: 据えた部品の識別子一覧を作る(&配置表),
        ベイ,
        入口のローカル方向: 材料.入口のローカル方向,
        外接箱: 建物の外接箱 {
            最小: 箱.最小(),
            最大: 箱.最大(),
        },
    })
}

/// 宣言した部品ではなく、実際に据わった部品だけを、据えた順のまま重複を除いて並べる。
/// 規則が候補として持つだけで1件も据えなかった部品を、編集画面へ「使う部品」として見せないためである。
fn 据えた部品の識別子一覧を作る(配置表: &部品ごとの配置表) -> Vec<String> {
    let mut 一覧: Vec<String> = Vec::new();
    for 据えた in 配置表.据えた順() {
        let 識別子 = 据えた.識別子().綴り().to_string();
        if !一覧.contains(&識別子) {
            一覧.push(識別子);
        }
    }
    一覧
}
