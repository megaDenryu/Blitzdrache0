//! 建物の規則を恒等配置で展開し、据わった全部品の実体の境界箱を畳んで外形を求める工程。

mod combined_box;
mod part_outlines;

use blitz_assembly::展開器;
use blitz_engine::個体配置;

use self::combined_box::建物全体の箱を作る;
use self::part_outlines::{部品のパス一覧を参照する, 部品の外形一覧を読む};
use super::catalog::{建物の外接箱, 建物外形カタログ, 建物定義};
use super::definition_source::{全定義, 建物定義の正本};
use super::error::建物外形カタログエラー;
use crate::loader::部品カタログの読み込み係;
use crate::runtime_compilation::source_location::外部ソースルート;

pub(super) fn 建物外形カタログを実体から組み立てる() -> Result<建物外形カタログ, 建物外形カタログエラー> {
    let 外部ルート = 外部ソースルート::解決する();
    let mut 定義一覧 = Vec::with_capacity(5);
    for 正本 in 全定義() {
        定義一覧.push(建物定義を実体から組み立てる(&外部ルート, 正本)?);
    }
    Ok(建物外形カタログ::定義一覧から生成する(定義一覧))
}

fn 建物定義を実体から組み立てる(
    外部ルート: &外部ソースルート,
    正本: 建物定義の正本,
) -> Result<建物定義, 建物外形カタログエラー> {
    let パス一覧 = 部品のパス一覧を参照する(外部ルート, &正本)?;
    let 部品一覧 = 部品の外形一覧を読む(&パス一覧, &正本)?;
    let カタログ = 部品カタログの読み込み係::パスの並びから生成する(&パス一覧).組み上げる().map_err(|原因| {
        建物外形カタログエラー::部品カタログを組み立てられない {
            建物定義: 正本.識別子.to_string(),
            原因: 原因.to_string(),
        }
    })?;
    let (規則, 種) = 正本
        .規則
        .規則と種の起点を組む()
        .map_err(|原因| 建物外形カタログエラー::規則を組み立てられない {
            建物定義: 正本.識別子.to_string(),
            原因,
        })?;
    let 根 = 個体配置::生成する([0.0; 3], [0.0, 0.0, 0.0, 1.0], [1.0; 3]).map_err(|原因| {
        建物外形カタログエラー::建物を展開できない {
            建物定義: 正本.識別子.to_string(),
            原因: 原因.to_string(),
        }
    })?;
    let 配置表 = 展開器::カタログを持たせて生成する(カタログ)
        .規則から展開する(&規則, 種, 根)
        .map_err(|原因| 建物外形カタログエラー::建物を展開できない {
            建物定義: 正本.識別子.to_string(),
            原因: 原因.to_string(),
        })?;
    let 箱 = 建物全体の箱を作る(&正本, &部品一覧, &配置表)?;
    Ok(建物定義 {
        識別子: 正本.識別子.to_string(),
        表示名: 正本.表示名.to_string(),
        用途: 正本.用途,
        部品の識別子一覧: 部品一覧.iter().map(|部品| 部品.識別子.綴り().to_string()).collect(),
        ベイ: 正本.ベイ,
        高さメートル: 箱.最大()[1] - 箱.最小()[1],
        入口のローカル方向: 正本.入口のローカル方向,
        外接箱: 建物の外接箱 {
            最小: 箱.最小(),
            最大: 箱.最大(),
        },
    })
}
