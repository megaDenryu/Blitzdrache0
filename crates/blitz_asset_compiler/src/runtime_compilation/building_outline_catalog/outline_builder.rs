use super::definition_source::{全定義, 建物定義の正本};
use super::error::建物外形カタログエラー;
use crate::runtime_compilation::source_location::外部ソースルート;

pub(super) fn 建物外形カタログを実体から組み立てる() -> Result<建物外形カタログ, 建物外形カタログエラー> {
    let 外部ルート = 外部ソースルート::解決する();
    if let 外部ソースルート::不在 { 診断 } = &外部ルート {
        return Err(建物外形カタログエラー::外部ソースルート不在(診断.clone()));
    }
    let mut 定義一覧 = Vec::with_capacity(5);
    for 正本 in 全定義() {
        定義一覧.push(建物定義を実体から組み立てる(&外部ルート, 正本)?);
    }
    Ok(建物外形カタログ::定義一覧から生成する(定義一覧))
}

fn 建物定義を実体から組み立てる(
    外部ルート: &外部ソースルート,
    正本: 建物定義の正本,
) -> Result<建物定義, 建物外形カタログエラー> {
    let パス一覧 = 部品のパス一覧を参照する(外部ルート, &正本)?;
    let 部品一覧 = 部品の外形一覧を読む(&パス一覧, &正本)?;
    let 配置表 = 建物の規則を恒等の姿勢で展開する(&パス一覧, &正本)?;
    let 箱 = 建物全体の箱を作る(&正本, &部品一覧, &配置表)?;
    受理条件を確かめる(&正本, &部品一覧, &配置表, &箱)?;
    Ok(建物定義 {
        識別子: 建物定義ID::生成する(正本.識別子).map_err(|原因| 建物外形カタログエラー::規則を組み立てられない {
            建物定義: 正本.識別子.to_string(),
            原因,
        })?,
        表示名: 正本.表示名.to_string(),
        用途: 正本.用途,
        部品の識別子一覧: 据えた部品の識別子一覧を作る(&配置表),
        ベイ: 正本.ベイ,
        入口のローカル方向: 正本.入口のローカル方向,
        外接箱: 建物の外接箱 {
            最小: 箱.最小(),
            最大: 箱.最大(),
        },
    })
}

/// 宣言した部品ではなく、実際に据わった部品だけを、据えた順のまま重複を除いて並べる。
/// 規則が候補として持つだけで1件も据えなかった部品を、編集画面へ「使う部品」として見せないためである。
fn 据えた部品の識別子一覧を作る(配置表: &部品ごとの配置表) -> Vec<String> {
    let mut 一覧: Vec<String> = Vec::new();
    for 据えた in 配置表.据えた順() {
        let 識別子 = 据えた.識別子().綴り().to_string();
        if !一覧.contains(&識別子) {
            一覧.push(識別子);
        }
    }
    一覧
}
