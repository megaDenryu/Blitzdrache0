//! 建物1件ぶんの組み立てを恒等配置で展開し、据わった全部品の実体の境界箱を畳んで外形を求める工程。
//! 由来が宣言の規則でも人が編集したベイ格子でも、展開から先の道筋はここ1本に合流する。

