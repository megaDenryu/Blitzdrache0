pub(crate) fn 識別子で引く(識別子: &str) -> Option<建物定義の正本> {
    全定義().into_iter().find(|定義| 定義.識別子 == 識別子)
}

pub(crate) fn 全建物の部品識別一覧() -> Vec<(&'static str, &'static str)> {
    let mut 一覧 = Vec::new();
    for 定義 in 全定義() {
        for 部品 in 定義.規則.部品一覧() {
            let 対 = (部品.安定id(), 部品.ソース相対パス());
            if !一覧.contains(&対) {
                一覧.push(対);
            }
        }
    }
    一覧
}

fn 定義(
    識別子: &'static str,
    表示名: &'static str,
    用途: 建物定義の用途,
    規則: 部品の組み立て規則の種類,
    横: u32,
    奥: u32,
    階: u32,
) -> 建物定義の正本 {
    建物定義の正本 {
        識別子,
        表示名,
        用途,
        規則,
        ベイ: ベイ構造 { 横, 奥, 階 },
        入口のローカル方向: 入口方向,
    }
}
