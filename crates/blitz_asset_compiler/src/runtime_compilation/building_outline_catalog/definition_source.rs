//! 建物定義5件の正本。識別子・表示名・用途・規則・部品・ベイ構造・入口方向を1件として持つ。

use super::catalog::{ベイ構造, 建物の入口方向, 建物定義の用途};
use crate::runtime_compilation::world::assembly_rule_choice::部品の組み立て規則の種類;

#[derive(Clone, Copy)]
pub(crate) struct 建物定義の正本 {
    pub 識別子: &'static str,
    pub 表示名: &'static str,
    pub 用途: 建物定義の用途,
    pub 規則: 部品の組み立て規則の種類,
    pub ベイ: ベイ構造,
    pub 入口のローカル方向: 建物の入口方向,
}
const 入口方向: 建物の入口方向 = 建物の入口方向 { x: 0.0, z: 1.0 };

