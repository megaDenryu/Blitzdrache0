//! 焼き上がりの報告を出す工程。受け取るのは焼き直しの勘定と置いた個体の勘定と実行時カタログ、
//! 出すのは検収が読む4本の行である。
//!
//! 4本を1箇所から出すのは、どれも「1回の焼き付けが何をしたか」を述べる同じ役割であり、行の並びが
//! 読み手の前提になるためである。焼く工程の途中へ散らすと、遠景を焼く枝を通ったかどうかで行の順が変わる。
//!
//! 行の綴りそのものは勘定の型が持つ。ここは並べて出すだけであり、綴りの写しを持たない。

use blitz_engine::カタログ;

use super::instance_tally::個体数の勘定;
use super::placed_instance_tally::置いた個体の勘定;
use crate::焼き直しの勘定;

pub(super) fn 焼き上がりの4行を出す(
    焼き直しの勘定: &焼き直しの勘定, 置いた個体の勘定: &置いた個体の勘定, 実行時カタログ: &カタログ
) {
    println!("[compile_assets] {}", 焼き直しの勘定.報告の行を作る());
    println!("[compile_assets] {}", 置いた個体の勘定.報告の行を作る());
    println!("[compile_assets] {}", 置いた個体の勘定.内訳の行を作る());
    println!(
        "[compile_assets] {}",
        個体数の勘定::実行時カタログから数える(実行時カタログ).報告の行を作る()
    );
}
