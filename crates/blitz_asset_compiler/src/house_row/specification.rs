//! 家並みの指定: 何をどれだけどう建てるかを1つの値で持つ型。
//!
//! 4つを1つの値にまとめるのは、どれも同じ1つの家並みを決める材料であり、別々の引数で受けると
//! 別の世界の規則と別の世界の部品の一覧を組み合わせても署名が通るためである。
//!
//! 部品を安定IDの一覧で持ち、部品IDの一覧で持たないのは、部品IDがglTFのファイル名から決まるためである。
//! 宣言の側が両方を書くと、ファイル名を変えたときに片方だけが残る二重管理になる。

use blitz_assembly::{生成の種, 組み立て規則};
use blitz_engine::アセットID;

use super::error::部品の家並みのコンパイルエラー;
use super::house_count::家並みの軒数;

pub struct 家並みの指定 {
    部品の安定id一覧: Vec<アセットID>,
    規則: 組み立て規則,
    軒数: 家並みの軒数,
    種の起点: 生成の種,
}

impl 家並みの指定 {
    /// 部品が1件も無い宣言を拒むのは、部品が無ければ規則がどの部品も引けず、
    /// 「カタログに無い」という規則の側の破れとして遠い場所で落ちるためである。
    pub fn 生成する(
        部品の安定id一覧: Vec<アセットID>,
        規則: 組み立て規則,
        軒数: 家並みの軒数,
        種の起点: 生成の種,
    ) -> Result<Self, 部品の家並みのコンパイルエラー> {
        if 部品の安定id一覧.is_empty() {
            return Err(部品の家並みのコンパイルエラー::部品が1件も宣言されていない);
        }
        Ok(Self {
            部品の安定id一覧,
            規則,
            軒数,
            種の起点,
        })
    }

    pub(super) fn 部品の安定id一覧(&self) -> &[アセットID] {
        &self.部品の安定id一覧
    }

    pub(super) fn 規則(&self) -> &組み立て規則 {
        &self.規則
    }

    pub(super) fn 軒数(&self) -> 家並みの軒数 {
        self.軒数
    }

    pub(super) fn 種の起点(&self) -> 生成の種 {
        self.種の起点
    }
}
