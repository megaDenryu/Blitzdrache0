//! 部品で建てた家並みを焼くときの失敗。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! アセットコンパイルエラーへ直に枝を足さずこの型を挟むのは、家並みだけが持つ前提(軒数・部品の宣言・規則と宣言の食い違い)を
//! 1箇所へ集めるためである。上位の型は`#[from]`で1枝だけを持ち、どの世界の失敗かが枝の名前で分かる。

use blitz_assembly::展開エラー;
use thiserror::Error;

use crate::loader::部品カタログの読み込みエラー;

#[derive(Debug, Error)]
pub enum 部品の家並みのコンパイルエラー {
    /// 1軒も建てない家並みは群を1つも持たず、絵にも計器にも何も出ない。宣言の書き誤りとして入口で拒む。
    #[error("家並みへ建てる軒数が1以上{上限}以下でない: {実値}")]
    軒数が範囲外 { 実値: usize, 上限: u16 },

    #[error("家並みが読む部品が1件も宣言されていない")]
    部品が1件も宣言されていない,

    #[error("部品カタログを組み上げられない: {0}")]
    部品カタログを組めない(#[from] 部品カタログの読み込みエラー),

    /// 展開が据えた部品が宣言の一覧に無いなら、規則が宣言していない部品を指している。
    #[error("展開が据えた部品{部品の綴り}の原型が家並みの宣言に無い")]
    据えた部品が宣言に無い { 部品の綴り: String },

    #[error("軒{軒番号}を展開できない: {誤り}")]
    軒を展開できない {
        軒番号: u16,
        #[source]
        誤り: 展開エラー,
    },
}
