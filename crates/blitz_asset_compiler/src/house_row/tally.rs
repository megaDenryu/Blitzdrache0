//! 家並みの勘定: 焼く工程が何を何件作ったかを数え上げ、報告の行を組み立てる型。
//!
//! **この行が段4の実証の期待値そのものである。** 検収はアプリが出したシーンパスの発行数と、この行が出した
//! プリミティブ数の総和を突き合わせる。期待値を検収の側に定数で持つと、部品を1つ足したときに検収だけが
//! 無言で通らなくなる。焼いた側が数えた値を渡すことで、部品の増減が両側へ同時に効く。
//!
//! 材質スロット数とプリミティブ数を両方数えるのは、描画発行がプリミティブごとに立つ一方で、
//! 設計の主張が材質スロット数で書かれているためである。2つが食い違ったらどちらかの前提が崩れている。
//!
//! 注意: 報告の行の綴りは`xtask/src/part_house_row_draw/compile_report.rs`が読み取る側として同じものを持つ。
//! 両側にあることは`cargo xtask conform`の綴りの契約の検査が守る。

use super::house_count::家並みの軒数;
use crate::loader::原型ソース;

pub(super) struct 家並みの勘定 {
    軒数: 家並みの軒数,
    部品の種類数: usize,
    材質スロット数の総和: usize,
    プリミティブ数の総和: usize,
    据えた部品の個体数: usize,
}

impl 家並みの勘定 {
    pub(super) fn 軒数から始める(軒数: 家並みの軒数) -> Self {
        Self {
            軒数,
            部品の種類数: 0,
            材質スロット数の総和: 0,
            プリミティブ数の総和: 0,
            据えた部品の個体数: 0,
        }
    }

    /// 群を1つ作るたびに、その部品の材質スロット数とプリミティブ数と個体の件数を積む。
    pub(super) fn 部品を1件数える(&mut self, 原型: &原型ソース, 個体の件数: usize) {
        self.部品の種類数 += 1;
        self.材質スロット数の総和 += 原型.材質集合.件数();
        self.プリミティブ数の総和 += 原型.段一覧.iter().map(|段| 段.プリミティブ列.len()).sum::<usize>();
        self.据えた部品の個体数 += 個体の件数;
    }

    pub(super) fn 報告を出す(&self) {
        println!("[compile_assets] {}", self.報告の行を作る());
    }

    fn 報告の行を作る(&self) -> String {
        format!(
            "部品の家並み: 建てた軒数={} 部品の種類数={} 材質スロット数の総和={} プリミティブ数の総和={} 据えた部品の個体数={}",
            self.軒数.値(),
            self.部品の種類数,
            self.材質スロット数の総和,
            self.プリミティブ数の総和,
            self.据えた部品の個体数
        )
    }
}
