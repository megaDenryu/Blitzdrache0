//! 家並みの展開係: 部品カタログと敷地を保持し、規則を軒数ぶん展開して1つの集約へまとめる操作サービス。
//!
//! 展開器と敷地を保持するのは、この2つが1回の家並みを焼くあいだ変わらないためである。軒ごとに引数で渡すと、
//! 別のカタログと別の敷地を組み合わせた呼び出しが型を通る。
//!
//! **集約がここで作られることが、発行数が軒数に比例しないことの実装である。** 軒ごとに出た配置表を
//! 部品の種類ごとの1つの配置列へ畳むため、軒数が増えても描画対象の数は変わらない。

use blitz_assembly::{展開器, 生成の種, 組み立て規則, 部品ごとの配置の集約, 部品カタログ};

use super::error::部品の家並みのコンパイルエラー;
use super::house_count::家並みの軒数;
use super::site::家並みの敷地;
use crate::error::アセットコンパイルエラー;

pub(super) struct 家並みの展開係<'格子> {
    展開器: 展開器,
    敷地: 家並みの敷地<'格子>,
}

impl<'格子> 家並みの展開係<'格子> {
    pub(super) fn 生成する(カタログ: 部品カタログ, 敷地: 家並みの敷地<'格子>) -> Self {
        Self {
            展開器: 展開器::カタログを持たせて生成する(カタログ),
            敷地,
        }
    }

    /// 軒ごとに種を分けて展開し、部品の種類ごとの配置列へまとめる。
    /// 種を軒番号で分けるのは、同じ種のままだと全軒が同じ形になり、組み合わせで違いを作る設計が絵に出ないためである。
    pub(super) fn 軒数ぶん展開する(
        &self,
        規則: &組み立て規則,
        種の起点: 生成の種,
        軒数: 家並みの軒数,
    ) -> Result<部品ごとの配置の集約, アセットコンパイルエラー> {
        let mut 集約 = 部品ごとの配置の集約::空から始める();
        for 軒番号 in 0..軒数.値() {
            let 根の配置 = self.敷地.軒の根の配置を求める(軒番号)?;
            let 種 = 種の起点.個体の番号で分けた種を作る(u64::from(軒番号));
            let 配置表 = self
                .展開器
                .規則から展開する(規則, 種, 根の配置)
                .map_err(|誤り| 部品の家並みのコンパイルエラー::軒を展開できない { 軒番号, 誤り })?;
            集約.配置表を1件取り込む(&配置表);
        }
        Ok(集約)
    }
}
