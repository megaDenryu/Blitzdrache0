//! 部品で建てた家並みのシーンを組み立てる工程。受け取るのは高さ格子と所有チャンクと家並みの指定、
//! 返すのは地面1つと部品の種類の数だけの群を持つシーンデータである。
//!
//! 地面を地形LODメッシュ群として焼くのは、見本の集落と同じ経路で焼くことで、軒の接地が描画される面と
//! 同じ求め方の上に乗るためである。
//!
//! 群を部品の種類ごとに1つだけ作ることが、この世界が実証する性質そのものである。軒数で伸びるのは
//! 群の中の配置列だけであり、描画対象の数は宣言した部品の種類の数を超えない。

use std::path::PathBuf;

use blitz_engine::{
    シーンデータ, チャンク座標, マテリアルデータ, 描画対象ID, 描画対象データ, 描画形状, 材質集合, 金属粗さPBRデータ
};

use super::expansion_run::家並みの展開係;
use super::parts::家並みの部品一式;
use super::site::家並みの敷地;
use super::specification::家並みの指定;
use super::tally::家並みの勘定;
use crate::assembled_scene::組み立てたシーン;
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子;
use crate::placed_instance_count::置いた個体の数;
use crate::scene_compiler::ソースアセットのコンパイル係;
use crate::terrain::lod_bake;
use crate::vegetation::group_object;

/// 地面の描画対象番号。1つの高さ格子が1つの描画対象になるため常にこの値であり、群はこの次から番号を取る。
const 地面の描画対象番号: u64 = 0;

impl ソースアセットのコンパイル係<'_> {
    pub(super) fn 部品で建てた家並みのシーンを組み立てる(
        &self,
        格子: &高さ格子,
        所有チャンク: チャンク座標,
        ソースパス: PathBuf,
        指定: &家並みの指定,
    ) -> Result<組み立てたシーン, アセットコンパイルエラー> {
        let 部品一式 = 家並みの部品一式::宣言から読み取る(self, 指定.部品の安定id一覧())?;
        let 敷地 = 家並みの敷地::生成する(格子, 指定.軒数(), self.配置の種を貸す());
        let 集約 =
            家並みの展開係::生成する(部品一式.カタログを組み上げる()?, 敷地).軒数ぶん展開する(指定.規則(), 指定.種の起点(), 指定.軒数())?;
        let 地面 = 描画対象データ::生成する(
            描画対象ID::生成する(地面の描画対象番号),
            所有チャンク,
            group_object::恒等変換を作る(),
            描画形状::地形LODメッシュ群(lod_bake::段別メッシュを焼く(格子)?),
            材質集合::単一材質から生成する(地面のマテリアルを作る()),
        );
        let mut 参照ファイル一覧 = vec![ソースパス];
        let mut 群の描画対象一覧 = Vec::with_capacity(集約.部品の種類数());
        let mut 置いた合計 = 置いた個体の数::零();
        let mut 勘定 = 家並みの勘定::軒数から始める(指定.軒数());
        let mut 描画対象番号 = 地面の描画対象番号;
        for 項目 in 集約.項目一覧() {
            描画対象番号 += 1;
            let 原型 = self.部品の原型ソースを読み込む(部品一式.原型の安定idを引く(項目.識別子())?)?;
            勘定.部品を1件数える(&原型, 項目.配置一覧().len());
            let 群 = group_object::群の描画対象を作る(描画対象番号, 所有チャンク, 原型.段一覧, 原型.材質集合, 項目.配置一覧().to_vec())?;
            置いた合計 = 置いた合計.足す(群.置いた個体の数)?;
            参照ファイル一覧.extend(原型.参照ファイル一覧);
            群の描画対象一覧.push(群.描画対象);
        }
        勘定.報告を出す();
        let シーン = シーンデータ::生成する(地面, 群の描画対象一覧, 参照ファイル一覧, None, Vec::new());
        Ok(組み立てたシーン::置いた個体の数を添えて生成する(
            シーン,
            置いた合計,
        ))
    }
}

/// 地面は草地の色の非金属として描く。建物の木と漆喰と屋根瓦のどれとも違う色にすることで、
/// 軒の輪郭と地面の境が絵の上で読み取れる。
fn 地面のマテリアルを作る() -> マテリアルデータ {
    マテリアルデータ::金属粗さPBR(金属粗さPBRデータ {
        ベースカラー: None,
        金属粗さ: None,
        法線マップ: None,
        ベースカラー係数: [0.30, 0.33, 0.22, 1.0],
        金属度係数: 0.0,
        粗さ係数: 0.92,
    })
}
