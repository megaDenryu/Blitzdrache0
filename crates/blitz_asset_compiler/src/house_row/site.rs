//! 家並みの敷地: 軒をどこへどの向きで建てるかを答える型。受け取るのは地面の高さ格子と軒数と配置の種、
//! 返すのは軒1件ぶんの根の配置である。
//!
//! 高さ格子を保持するのは、根の高さがその場所の地表高さで決まるためである。呼び出し側へ格子を持ち回らせると、
//! 別の世界の地面から高さを引いた根の配置が型を通る。
//!
//! 向きを4分の1回転の4通りに限るのは、軒の間隔が家の奥行より少ししか広くなく、斜めに回すと隣の家と重なるためである。
//! 4通りでも棟の向きが揃わなくなり、格子に並んだ作り物らしさは消える。

use blitz_engine::個体配置;
use blitz_math::{決定的な値の生成器, 用途番号};

use super::house_count::家並みの軒数;
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子;
use crate::placement::{天頂まわりの回転を作る, 配置の種};
use crate::terrain::ground_height;

/// 隣り合う軒の間隔。実データの家は幅6.7メートル・奥行6.0メートルであり、出窓が前後へ0.8メートル張り出す。
/// 10メートル取ると、どの向きへ回しても隣との間に1メートル以上の道が残る。
const 軒の間隔メートル: f32 = 10.0;

/// 軒の向きを決める用途の番号。散布は1から7、部品の展開は100番台を使うため、家並みの敷地は200番台から採る。
/// 同じ種を使う層が同じ番号を使うと同じ値が出るため、番号は層ごとに重ならない範囲から採る。
const 軒の向きの用途番号: u64 = 201;

/// 敷地の混合の固定の種。世界を変えない限り同じ値を使い、同じ宣言から同じ配置を得る。
const 敷地の種: u64 = 0x4861_7573_6552_6F77;

pub(super) struct 家並みの敷地<'格子> {
    格子: &'格子 高さ格子,
    軒数: 家並みの軒数,
    向きの生成器: 決定的な値の生成器,
}

impl<'格子> 家並みの敷地<'格子> {
    pub(super) fn 生成する(格子: &'格子 高さ格子, 軒数: 家並みの軒数, 配置の種: 配置の種) -> Self {
        Self {
            格子,
            軒数,
            向きの生成器: 決定的な値の生成器::種の値から生成する(敷地の種 ^ 配置の種.混合へ足す値()),
        }
    }

    /// 軒1件の根の配置。水平位置は格子の升目の中央、高さはその点の地表高さ、向きは4分の1回転の4通りから選ぶ。
    pub(super) fn 軒の根の配置を求める(&self, 軒番号: u16) -> Result<個体配置, アセットコンパイルエラー> {
        let 列数 = self.軒数.格子の列数();
        let 水平 = self.升目の中心を求める(軒番号 % 列数, 軒番号 / 列数);
        let 高さ = ground_height::地表高さを求める(self.格子, 水平[0], 水平[1])?;
        let 回転 = 天頂まわりの回転を作る(self.四分の一回転の向きを選ぶ(軒番号));
        Ok(個体配置::生成する([水平[0], 高さ, 水平[1]], 回転, [1.0; 3])?)
    }

    /// 格子の中心をチャンクの中央へ合わせた升目の中心。横と奥の2成分を返す。
    fn 升目の中心を求める(&self, 列: u16, 行: u16) -> [f32; 2] {
        let 中央 = self.格子.諸元().一辺メートル() * 0.5;
        let 中心の列 = (f32::from(self.軒数.格子の列数()) - 1.0) * 0.5;
        let 中心の行 = (f32::from(self.軒数.格子の行数()) - 1.0) * 0.5;
        [
            中央 + (f32::from(列) - 中心の列) * 軒の間隔メートル,
            中央 + (f32::from(行) - 中心の行) * 軒の間隔メートル,
        ]
    }

    /// 0以上1未満の値を4等分し、越えた境界の数だけ4分の1回転を重ねた角度を返す。
    /// 小数から整数への変換を持たないのは、標準ライブラリが型付きの変換を持たず、`as`による縮小変換を規約が禁じているためである。
    fn 四分の一回転の向きを選ぶ(&self, 軒番号: u16) -> f32 {
        let 値 = self
            .向きの生成器
            .零以上一未満(u64::from(軒番号), 用途番号::番号から生成する(軒の向きの用途番号));
        let mut 角度 = 0.0;
        for 境界 in [0.25, 0.5, 0.75] {
            if 値 >= 境界 {
                角度 += std::f32::consts::FRAC_PI_2;
            }
        }
        角度
    }
}
