//! 家並みの軒数: 1つのチャンクへ建てる家の数。
//!
//! 裸のusizeで持たないのは、軒数と部品の件数と個体の件数がどれも数であり、引数として並べると取り違えても署名が通るためである。
//! 上限をu16の範囲に置くのは、軒番号をそのまま格子の行と列へ割るためである。
//!
//! 建てる場所の並べ方をこの型が答えるのは、列数が軒数だけから決まるためである。呼び出し側が平方根を取り直すと、
//! 10軒と100軒で違う丸め方をした形が生まれる。

use super::error::部品の家並みのコンパイルエラー;

/// 軒数の上限。一辺100メートルのチャンクへ間隔10メートルで並べられるのは高々100軒であり、
/// 段4の実証はその範囲で足りる。上限を置くと格子の列数の探索がu16の範囲で必ず止まる。
const 軒数の上限: u16 = 1024;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct 家並みの軒数(u16);

impl 家並みの軒数 {
    pub fn 生成する(軒数: usize) -> Result<Self, 部品の家並みのコンパイルエラー> {
        let 範囲外 = || 部品の家並みのコンパイルエラー::軒数が範囲外 {
            実値: 軒数,
            上限: 軒数の上限,
        };
        let 値 = u16::try_from(軒数).map_err(|_| 範囲外())?;
        if 値 == 0 || 値 > 軒数の上限 {
            return Err(範囲外());
        }
        Ok(Self(値))
    }

    pub fn 値(self) -> u16 {
        self.0
    }

    /// 軒を並べる正方に近い格子の列数。軒数を覆う最小の正方格子の一辺である。
    pub fn 格子の列数(self) -> u16 {
        let mut 列数 = 1_u16;
        while u32::from(列数) * u32::from(列数) < u32::from(self.0) {
            列数 += 1;
        }
        列数
    }

    /// その列数で軒を並べたときの行数。最後の行は埋まりきらないことがある。
    pub fn 格子の行数(self) -> u16 {
        let 列数 = self.格子の列数();
        self.0.div_ceil(列数)
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::家並みの軒数;

    #[test]
    fn 零軒と上限超えを拒む() {
        assert!(家並みの軒数::生成する(0).is_err());
        assert!(家並みの軒数::生成する(100_000).is_err());
    }

    #[test]
    fn 格子は軒数を覆う() {
        for 軒数 in [1_usize, 2, 9, 10, 99, 100] {
            let 値 = 家並みの軒数::生成する(軒数).unwrap();
            let 収まる数 = u32::from(値.格子の列数()) * u32::from(値.格子の行数());
            assert!(収まる数 >= u32::try_from(軒数).unwrap(), "{軒数}軒が格子へ収まらない");
        }
    }

    #[test]
    fn 百軒は十列十行になる() {
        let 百軒 = 家並みの軒数::生成する(100).unwrap();
        assert_eq!(百軒.格子の列数(), 10);
        assert_eq!(百軒.格子の行数(), 10);
    }
}
