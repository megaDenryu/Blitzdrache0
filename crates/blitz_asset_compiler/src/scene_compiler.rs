//! ソースアセットのコンパイル係: 1回の焼き付けが通しで使うカタログとテクスチャ格納方針を保持し、
//! 安定IDから実行時形式のシーンを焼く操作をメソッドで公開する操作サービス。
//!
//! 依存を保持させるのは、カタログと格納方針が焼く対象ごとに変わらず、世界1つを焼く間ずっと同じ2つだからである。
//! 引数で渡し歩くと、どの工程が何に触れるかが署名から読めなくなり、別の世界のカタログを混ぜても型が通る。
//! 焼く工程は世界の種類ごとにこの型のメソッドとして分かれており、その置き場は`terrain`・`vegetation`・`village`・
//! `visual_sample`・`fixed_placement`・`compile::source_scene`・`loader`である。
//!
//! カタログを外へ貸さないのは、この係がカタログへ問うのが「安定IDが指すソースの置き場」の1つだけだからである。
//! 参照: `_doc/計画/ユビキタス言語.md`「ソースアセットのコンパイル係」

use std::path::Path;

use blitz_engine::{アセットID, カタログ};

use crate::error::アセットコンパイルエラー;
use crate::texture_storage::テクスチャ格納方針;

pub struct ソースアセットのコンパイル係<'カタログ> {
    カタログ: &'カタログ カタログ,
    テクスチャ格納方針: テクスチャ格納方針,
}

impl<'カタログ> ソースアセットのコンパイル係<'カタログ> {
    pub fn 生成する(カタログ: &'カタログ カタログ, テクスチャ格納方針: テクスチャ格納方針) -> Self {
        Self {
            カタログ,
            テクスチャ格納方針,
        }
    }

    /// 保持している格納方針を工程へ貸す。焼く側が方針を持参するのではなく、この係が自分の持ち物を渡す向きである。
    pub(crate) fn テクスチャの格納方針(&self) -> テクスチャ格納方針 {
        self.テクスチャ格納方針
    }

    /// 安定IDが指すソースの置き場を返す。カタログに載っていない安定IDは型付きエラーにして、
    /// 「ソースが無い」という遠い場所の失敗になる前にここで止める。
    /// 呼び出し側へも開けるのは、増分の鍵が「今回の宣言が指すソース」を材料に要り、その1点だけがカタログへの問いだからである。
    pub fn 安定idが指すソースのパスを参照する(
        &self,
        id: &アセットID,
    ) -> Result<&'カタログ Path, アセットコンパイルエラー> {
        self.カタログ
            .パスを参照する(id)
            .ok_or_else(|| アセットコンパイルエラー::カタログ未登録(id.clone()))
    }
}
