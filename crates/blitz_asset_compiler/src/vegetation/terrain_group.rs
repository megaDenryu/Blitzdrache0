//! 地形チャンクへ同居させるインスタンス群の描画対象を組み立てる工程。受け取るのはカタログと同居の指定、所有チャンク、
//! 描画対象番号、地表高さを返す関数であり、返すのは描画対象データと原型ソースの参照ファイル一覧である。
//! 群の中身の作り方は1チャンク1群の植生世界と同じであり、違うのは配置の決め方(`terrain_placement`)と共有マテリアルだけである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「ストリーミング統合」

use std::path::PathBuf;

use blitz_engine::{
    アセットID, カタログ, チャンク座標, マテリアルデータ, 描画対象データ, 材質集合, 金属粗さPBRデータ
};

use super::{group_object, terrain_placement};
use crate::error::アセットコンパイルエラー;
use crate::loader::原型ソースを読み込む;

/// 地形チャンクへ同居させる植生の指定。原型の安定IDと個体数を持つ。地形の側はこの値の有無だけで同居させるかを決める。
pub struct 同居植生の指定 {
    pub 原型id: アセットID,
    pub 個体数: usize,
}

pub struct 地形同居の群 {
    pub 描画対象: 描画対象データ,
    pub 参照ファイル一覧: Vec<PathBuf>,
}

pub fn 地形同居の群を作る(
    カタログ: &カタログ,
    指定: &同居植生の指定,
    所有チャンク: チャンク座標,
    描画対象番号: u64,
    地表高さを求める: impl Fn(f32, f32) -> Result<f32, アセットコンパイルエラー>,
) -> Result<地形同居の群, アセットコンパイルエラー> {
    let 原型ソース = 原型ソースを読み込む(カタログ, &指定.原型id)?;
    let 配置一覧 = terrain_placement::配置列を作る(所有チャンク, 指定.個体数, 地表高さを求める)?;
    let 描画対象 = group_object::群の描画対象を作る(
        描画対象番号,
        所有チャンク,
        原型ソース.段一覧,
        材質集合::単一材質から生成する(植生マテリアルを作る()),
        配置一覧,
    )?;
    Ok(地形同居の群 {
        描画対象,
        参照ファイル一覧: 原型ソース.参照ファイル一覧,
    })
}

/// 群の共有マテリアルは原型でなく外側の描画対象データが持つため、原型ソースのマテリアルをそのまま使わずここで選び直す。
/// 地形が白の非金属で描かれるのに対して緑の非金属にするのは、読み戻し画像で植生の画素と地表の画素を色だけで見分けるためである。
/// 原型ソースのマテリアルは既定のまま(ベースカラー白)であり、それでは地形と同じ色になる。
fn 植生マテリアルを作る() -> マテリアルデータ {
    マテリアルデータ::金属粗さPBR(金属粗さPBRデータ {
        ベースカラー: None,
        金属粗さ: None,
        法線マップ: None,
        ベースカラー係数: [0.12, 0.62, 0.20, 1.0],
        金属度係数: 0.0,
        粗さ係数: 0.9,
    })
}
