//! 添字と用途から0以上1未満の小数を決める固定の混合関数。担当するのは値の決定だけであり、何に使うかを知らない。
//! 生成器の可変状態を持たないため、走査順を変えても同じ添字と同じ用途からは常に同じ値が出る。これが配置生成の決定性の根拠である。

/// 用途の識別。同じ添字から複数の独立した値を得るため、用途ごとに混合の入力を変える。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 用途 {
    X方向の揺らぎ,
    Z方向の揺らぎ,
    向き,
    大きさ,
    周方向の揺らぎ,
    半径方向の揺らぎ,
}

impl 用途 {
    fn 番号(self) -> u64 {
        match self {
            Self::X方向の揺らぎ => 1,
            Self::Z方向の揺らぎ => 2,
            Self::向き => 3,
            Self::大きさ => 4,
            Self::周方向の揺らぎ => 5,
            Self::半径方向の揺らぎ => 6,
        }
    }
}

pub(crate) fn 零以上一未満(種: u64, 添字: u64, 用途: 用途) -> f32 {
    let 上位 = 混ぜる(種 ^ 混ぜる(添字.wrapping_mul(0x9E37_79B9_7F4A_7C15) ^ 用途.番号())) >> 48;
    let 十六ビット = match u16::try_from(上位) {
        Ok(値) => 値,
        Err(_) => panic!("48ビット右シフトの結果がu16に収まらないという不変条件に違反した"),
    };
    f32::from(十六ビット) / 65_536.0
}

/// splitmix64の混合段。入力の1ビットの違いを出力全体へ広げるため、乗算と右シフトの排他的論理和を3回重ねる。
fn 混ぜる(値: u64) -> u64 {
    let mut z = 値.wrapping_add(0x9E37_79B9_7F4A_7C15);
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}
