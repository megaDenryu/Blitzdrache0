//! 群の保守的な境界を求める工程。受け取るのは原型の全メッシュLOD段と配置列、返すのは群の包囲領域と原型の境界球である。
//! 原型の境界球は全段の頂点の和集合から作るため、どの段を描いても球からはみ出さない。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「インスタンス群の表現」

use blitz_engine::{メッシュデータ, 個体配置, 境界球, 群境界, 軸平行包囲領域};
use blitz_math::{メートル, ローカル, 位置};

use crate::error::アセットコンパイルエラー;

pub(crate) fn 境界を求める(
    段一覧: &[メッシュデータ], 配置一覧: &[個体配置]
) -> Result<群境界, アセットコンパイルエラー> {
    let (最小, 最大) = 頂点の包囲を求める(段一覧)?;
    let 中心 = [0, 1, 2].map(|軸| (最小[軸] + 最大[軸]) * 0.5);
    let 半径 = 段一覧
        .iter()
        .flat_map(|段| &段.頂点一覧)
        .map(|頂点| 距離(頂点.位置, 中心))
        .fold(0.0_f32, f32::max);
    if 半径 <= 0.0 {
        return Err(アセットコンパイルエラー::植生原型の広がりなし);
    }
    let 球 = 境界球::生成する(中心, 半径)?;
    Ok(群境界::生成する(群の包囲領域を求める(中心, 半径, 配置一覧)?, 球))
}

/// 個体ごとに原型の境界球を配置で写し、その球を覆う直方体の和集合を取る。回転で向きが変わっても球は変わらないため、球のまま覆えば保守的である。
fn 群の包囲領域を求める(
    中心: [f32; 3],
    半径: f32,
    配置一覧: &[個体配置],
) -> Result<軸平行包囲領域, アセットコンパイルエラー> {
    let mut 最小 = [f32::INFINITY; 3];
    let mut 最大 = [f32::NEG_INFINITY; 3];
    for 配置 in 配置一覧 {
        let 写した中心 = 配置.変換を作る().適用する(位置::<ローカル>::生成する(
            メートル::生成する(中心[0]),
            メートル::生成する(中心[1]),
            メートル::生成する(中心[2]),
        ));
        let 座標 = [写した中心.x().値(), 写した中心.y().値(), 写した中心.z().値()];
        let 広がり = 半径 * 配置.スケール().into_iter().map(f32::abs).fold(0.0_f32, f32::max);
        for 軸 in 0..3 {
            最小[軸] = 最小[軸].min(座標[軸] - 広がり);
            最大[軸] = 最大[軸].max(座標[軸] + 広がり);
        }
    }
    Ok(軸平行包囲領域::生成する(最小, 最大)?)
}

fn 頂点の包囲を求める(段一覧: &[メッシュデータ]) -> Result<([f32; 3], [f32; 3]), アセットコンパイルエラー> {
    let mut 最小 = [f32::INFINITY; 3];
    let mut 最大 = [f32::NEG_INFINITY; 3];
    let mut 頂点数 = 0usize;
    for 段 in 段一覧 {
        for 頂点 in &段.頂点一覧 {
            頂点数 += 1;
            for 軸 in 0..3 {
                最小[軸] = 最小[軸].min(頂点.位置[軸]);
                最大[軸] = 最大[軸].max(頂点.位置[軸]);
            }
        }
    }
    if 頂点数 == 0 {
        return Err(アセットコンパイルエラー::植生原型の広がりなし);
    }
    Ok((最小, 最大))
}

fn 距離(位置: [f32; 3], 中心: [f32; 3]) -> f32 {
    let 差 = [0, 1, 2].map(|軸| 位置[軸] - 中心[軸]);
    (差[0] * 差[0] + 差[1] * 差[1] + 差[2] * 差[2]).sqrt()
}
