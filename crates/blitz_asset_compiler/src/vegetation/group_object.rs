//! 原型ソースと配置列から、インスタンス群を1つ持つ描画対象を組み立てる工程。
//! 受け取るのは原型の段一覧と共有する材質集合と配置列と所有チャンク、返すのは描画対象データである。
//! 境界の算出・原型の生成・群の生成の3つを1箇所へ集めるのは、この3つが「境界が中身を覆う」という
//! ひとつの不変条件を分担しており、順序を取り違えると検査を素通りするためである。
//! 群のローカルからワールドへの変換を恒等にするのは、個体の配置がチャンクアンカー相対で焼かれており、
//! 群そのものにはアンカーからのずれが無いためである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「インスタンス群の表現」

use blitz_engine::{
    インスタンス群, チャンク座標, メッシュデータ, 個体配置, 原型, 描画対象ID, 描画対象データ, 描画形状, 材質集合
};
use blitz_math::{クォータニオン, メートル, ローカル, ワールド, 位置, 変換};

use super::bounds;
use crate::error::アセットコンパイルエラー;

pub(crate) fn 群の描画対象を作る(
    描画対象番号: u64,
    所有チャンク: チャンク座標,
    段一覧: Vec<メッシュデータ>,
    材質集合: 材質集合,
    配置一覧: Vec<個体配置>,
) -> Result<描画対象データ, アセットコンパイルエラー> {
    let 境界 = bounds::境界を求める(&段一覧, &配置一覧)?;
    let 群 = インスタンス群::生成する(原型::生成する(段一覧)?, 配置一覧, 境界)?;
    Ok(描画対象データ::生成する(
        描画対象ID::生成する(描画対象番号),
        所有チャンク,
        恒等変換を作る(),
        描画形状::インスタンス群(群),
        材質集合,
    ))
}

pub(crate) fn 恒等変換を作る() -> 変換<ローカル, ワールド> {
    let 原点 = 位置::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0));
    let 回転 = match クォータニオン::<ローカル, ワールド>::生成する(0.0, 0.0, 0.0, 1.0) {
        Ok(値) => 値,
        Err(誤り) => panic!("原型の恒等回転が検証を満たさない: {誤り}"),
    };
    変換::trsから生成する(原点, 回転, [1.0; 3])
}
