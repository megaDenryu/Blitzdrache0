//! 地形チャンクへ同居させる個体の配置列を決める工程。受け取るのはチャンク座標と個体数と地表高さを返す関数、
//! 返すのはチャンクアンカー相対の配置列である。
//! 走査順は添字の昇順に固定し、値はチャンク座標と添字だけから決まる混合関数で作るため、同じチャンクと同じ個体数からは常に同じ配置列を得る。
//! チャンク座標を種へ混ぜるのは、25チャンクが同じ並びを持つとチャンクの境目で配置の繰り返しが絵に出るためである。
//! 平行移動のYを地表高さにするのは、原型の直方体が底面をy=0に持ち、その値がそのまま接地面になるためである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「ストリーミング統合」

use blitz_engine::{チャンク座標, 個体配置};

use super::deterministic_value::{用途, 零以上一未満};
use crate::error::アセットコンパイルエラー;

/// 配置を敷き詰める正方領域の一辺。一辺100メートルのチャンクの内側に6メートルの余白を残す。
/// 余白を置くのは、格子の揺らぎと個体の広がりを足してもチャンクの外へ出さないためである。
const 配置領域の一辺メートル: f32 = 88.0;

/// 領域の中心。チャンクの大域原点はX最小・Z最小の角にあるため、一辺100メートルの半分だけ内側がチャンクの中央になる。
const 配置領域の中心メートル: f32 = 50.0;

/// 格子の刻みに対する揺らぎの比率。格子らしさを消しつつ、隣り合う個体が融合しない幅に留める。
const 揺らぎ比率: f32 = 0.15;

/// 個体の大きさの範囲。原型の粗い段は高さ1メートルであり、この倍率で3から4メートルの柱になる。
/// 一辺100メートルのチャンクを5×5並べた世界を距離150メートルの俯瞰から見たとき、1体が画素の塊として読み取れる高さである。
const 大きさの下限: f32 = 3.0;
const 大きさの上限: f32 = 4.0;

/// 混合関数の固定の種。チャンク座標の永続化番号との排他的論理和を取ってから混合へ渡すため、チャンクごとに別の並びになる。
const 種: u64 = 0x4F57_3420_5465_7272;

/// 格子の列数がu16に収まる上限。これを超える個体数は配置の添字をu16で扱えなくなるため受け取らない。
const 個体数の上限: usize = 65_535 * 65_535;

pub(crate) fn 配置列を作る(
    所有チャンク: チャンク座標,
    個体数: usize,
    地表高さを求める: impl Fn(f32, f32) -> Result<f32, アセットコンパイルエラー>,
) -> Result<Vec<個体配置>, アセットコンパイルエラー> {
    if 個体数 == 0 || 個体数 > 個体数の上限 {
        return Err(アセットコンパイルエラー::植生個体数不正(個体数));
    }
    let チャンクの種 = 種 ^ 所有チャンク.番号を返す();
    let 列数 = 正方格子の列数(個体数);
    let 刻み = 配置領域の一辺メートル / f32::from(列数);
    let 中心添字 = (f32::from(列数) - 1.0) * 0.5;
    let mut 配置一覧 = Vec::with_capacity(個体数);
    for 添字 in 0..個体数 {
        let 添字u64 = u64::try_from(添字).map_err(|_| アセットコンパイルエラー::植生個体数不正(個体数))?;
        let 列 = f32::from(整数へ変換する(添字 % usize::from(列数), 個体数)?);
        let 行 = f32::from(整数へ変換する(添字 / usize::from(列数), 個体数)?);
        let x = 座標を求める(列, 中心添字, 刻み, 零以上一未満(チャンクの種, 添字u64, 用途::X方向の揺らぎ));
        let z = 座標を求める(行, 中心添字, 刻み, 零以上一未満(チャンクの種, 添字u64, 用途::Z方向の揺らぎ));
        let 回転 = y軸回転を作る(零以上一未満(チャンクの種, 添字u64, 用途::向き));
        let 倍率 = 大きさの下限 + (大きさの上限 - 大きさの下限) * 零以上一未満(チャンクの種, 添字u64, 用途::大きさ);
        配置一覧.push(個体配置::生成する([x, 地表高さを求める(x, z)?, z], 回転, [倍率; 3])?);
    }
    Ok(配置一覧)
}

fn 座標を求める(添字: f32, 中心添字: f32, 刻み: f32, 揺らぎ: f32) -> f32 {
    配置領域の中心メートル + (添字 - 中心添字) * 刻み + (揺らぎ * 2.0 - 1.0) * 刻み * 揺らぎ比率
}

/// Y軸まわりの回転だけを作る。個体は地面に立つため、傾ける自由度をこの段では持たせない。
fn y軸回転を作る(比率: f32) -> [f32; 4] {
    let 半角 = 比率 * std::f32::consts::PI;
    [0.0, 半角.sin(), 0.0, 半角.cos()]
}

fn 正方格子の列数(個体数: usize) -> u16 {
    let mut 列数 = 1u16;
    while usize::from(列数).saturating_mul(usize::from(列数)) < 個体数 {
        列数 += 1;
    }
    列数
}

fn 整数へ変換する(値: usize, 個体数: usize) -> Result<u16, アセットコンパイルエラー> {
    u16::try_from(値).map_err(|_| アセットコンパイルエラー::植生個体数不正(個体数))
}
