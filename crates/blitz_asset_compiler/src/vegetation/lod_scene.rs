//! 個体別LODの検収用シーンを焼く入口。担当するのは「どの配置で焼くか」の選択だけであり、
//! 配置の座標は`lod_placement`が、群の組み立ては`group_object`が持つ。
//! 床を同居させないのは、この検収が原型の段ごとのジオメトリの違いを背景色との差で数えるためであり、
//! 受け手の床があると個体と床の明度が並んで判定の境目が曖昧になる。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「段階導入」

use blitz_engine::{アセットID, カタログ, シーンを実行時形式へ格納する, シーンデータ, チャンク座標};

use super::{group_object, lod_placement};
use crate::compile::{コンパイル済みシーン, メタデータを集計する};
use crate::error::アセットコンパイルエラー;
use crate::loader::原型ソースを読み込む;

/// この世界のチャンクは群1つだけを持つ。
const 群の描画対象番号: u64 = 0;

pub fn 植生詳細段シーンをコンパイルする(
    カタログ: &カタログ,
    id: &アセットID,
    所有チャンク: チャンク座標,
) -> Result<コンパイル済みシーン, アセットコンパイルエラー> {
    let シーン = シーンを組み立てる(カタログ, id, 所有チャンク)?;
    let メタデータ = メタデータを集計する(&シーン)?;
    let 実行時バイト列 = シーンを実行時形式へ格納する(&シーン)?;
    Ok(コンパイル済みシーン {
        実行時バイト列,
        ソース依存一覧: シーン.参照ファイル一覧,
        メタデータ,
    })
}

fn シーンを組み立てる(
    カタログ: &カタログ,
    id: &アセットID,
    所有チャンク: チャンク座標,
) -> Result<シーンデータ, アセットコンパイルエラー> {
    let 原型ソース = 原型ソースを読み込む(カタログ, id)?;
    let 対象 = group_object::群の描画対象を作る(
        群の描画対象番号,
        所有チャンク,
        原型ソース.段一覧,
        原型ソース.マテリアル,
        lod_placement::配置列を作る()?,
    )?;
    Ok(シーンデータ::生成する(
        対象,
        Vec::new(),
        原型ソース.参照ファイル一覧,
        None,
        Vec::new(),
    ))
}
