//! 影の視距離の検収に使う固定配置。受け取る値は無く、返すのはチャンクの基準原点からの相対の配置列である。
//!
//! 置くのは2体だけである。1体はカメラから遠く、ほぼ水平の方向光で近距離の床へ長い影を落とす。もう1体はカメラの近くにあり、
//! 自分の足元へ短い影を落とす。**この世界は影の視距離(β)の危険を露出する負の対照である。** 中心距離だけで切る計測専用の
//! 切断では、遠い個体が近距離の床へ落とす長い影も一緒に消える。2体の影が受光面の別の場所へ落ちるようZをずらしてあり、
//! どちらが消えたかを画素で分けて読める。
//!
//! 注意: 将来、保護契約を持つ実装(光の方向へ伸ばしたキャスターの境界と保護したい受光領域の交差で残す形)を入れたときは、
//! この世界の期待値は「遠方キャスターの影が消える」から「消えない」へ反転する。世界そのものは作り直さない。
//! 座標は`crates/blitz_app/src/app/scene_camera.rs`の植生シーンの初期カメラと
//! `crates/blitz_app/src/app/scene_lighting.rs`の検収用ライト方針を前提に固定している。

use blitz_engine::個体配置;

use crate::error::アセットコンパイルエラー;

/// カメラの近くに置く対照。チャンク中央から+Zへ12メートルずらし、遠方キャスターの影が落ちる帯と重ならない位置にする。
const 近距離対照の平行移動: [f32; 3] = [50.0, 0.0, 62.0];

/// カメラから遠く、ほぼ水平の方向光で画面内の床へ影を落とす個体。倍率12は高さ36メートルに当たり、
/// 影の先端が画面中央付近の床へ届く(`cull_placement`の影投げと同じ寸法である)。
const 遠方キャスターの平行移動: [f32; 3] = [150.0, 0.0, 50.0];
const 遠方キャスターの倍率: f32 = 12.0;

const 恒等回転: [f32; 4] = [0.0, 0.0, 0.0, 1.0];

pub(super) fn 配置列を作る() -> Result<Vec<個体配置>, アセットコンパイルエラー> {
    Ok(vec![
        個体配置::生成する(近距離対照の平行移動, 恒等回転, [1.0; 3])?,
        個体配置::生成する(遠方キャスターの平行移動, 恒等回転, [遠方キャスターの倍率; 3])?,
    ])
}
