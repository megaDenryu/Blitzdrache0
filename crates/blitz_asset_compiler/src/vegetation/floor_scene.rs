//! インスタンス群1つと、その影を受ける床の通常メッシュ1つを同じチャンクへ同居させたシーンを組み立てる工程。
//! 受け取るのは原型の安定IDと配置列、返すのはコンパイル済みシーンである。配置列だけが検収ごとに違うため、
//! 床の寸法・描画対象番号・原型の取り出し方はこの工程が持つ。
//! 床を足すのは、影が画面内に残ることを画素で確かめるには受け手が要るためである。
//! 床は個体が1体の通常メッシュになるため、可視判定の対象にならない経路も同じシーンで通る。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「段階導入」

use blitz_engine::{アセットID, シーンデータ, チャンク座標, 個体配置, 描画対象ID, 描画対象データ, 描画形状};
use blitz_math::{クォータニオン, メートル, ローカル, ワールド, 位置, 変換};

use super::group_object;
use crate::compile::コンパイル済みシーン;
use crate::error::アセットコンパイルエラー;
use crate::scene_compiler::ソースアセットのコンパイル係;

const 群の描画対象番号: u64 = 0;
const 床の描画対象番号: u64 = 1;

/// 床の中心と寸法。チャンク中央へ置き、原型の直方体を水平方向へ広げて厚さを潰した板にする。
/// 半辺0.8メートルの原型を60倍すると一辺96メートルになり、カメラに写る範囲と影の落ちる範囲をどちらも覆う。
const 床の中心メートル: f32 = 50.0;
const 床の水平倍率: f32 = 60.0;
const 床の垂直倍率: f32 = 0.02;

impl ソースアセットのコンパイル係<'_> {
    pub(super) fn 群と床のシーンをコンパイルする(
        &self,
        id: &アセットID,
        所有チャンク: チャンク座標,
        配置一覧: Vec<個体配置>,
    ) -> Result<コンパイル済みシーン, アセットコンパイルエラー> {
        let シーン = self.群と床のシーンを組み立てる(id, 所有チャンク, 配置一覧)?;
        コンパイル済みシーン::シーンデータから焼く(シーン)
    }

    fn 群と床のシーンを組み立てる(
        &self,
        id: &アセットID,
        所有チャンク: チャンク座標,
        配置一覧: Vec<個体配置>,
    ) -> Result<シーンデータ, アセットコンパイルエラー> {
        let 原型ソース = self.原型ソースを読み込む(id)?;
        let 床メッシュ = 最詳細段を複製する(&原型ソース.段一覧);
        let 群対象 =
            group_object::群の描画対象を作る(群の描画対象番号, 所有チャンク, 原型ソース.段一覧, 原型ソース.材質集合.clone(), 配置一覧)?;
        let 床対象 = 描画対象データ::生成する(
            描画対象ID::生成する(床の描画対象番号),
            所有チャンク,
            床の変換を作る(),
            描画形状::通常メッシュ(床メッシュ),
            原型ソース.材質集合,
        );
        Ok(シーンデータ::生成する(
            群対象,
            vec![床対象],
            原型ソース.参照ファイル一覧,
            None,
            Vec::new(),
        ))
    }
}

/// 床は原型の最詳細段を平たく潰した板である。粗い段を使うと影の受け手の形が段の選択で変わり、
/// 影の画素判定が受け手側の都合で動いてしまう。
fn 最詳細段を複製する(段一覧: &[blitz_engine::メッシュデータ]) -> blitz_engine::メッシュデータ {
    match 段一覧.first() {
        Some(メッシュ) => メッシュ.clone(),
        None => panic!("原型ソースの段一覧が空であるという不変条件に違反した"),
    }
}

fn 床の変換を作る() -> 変換<ローカル, ワールド> {
    let 中心 = 位置::生成する(
        メートル::生成する(床の中心メートル),
        メートル::生成する(0.0),
        メートル::生成する(床の中心メートル),
    );
    let 回転 = match クォータニオン::<ローカル, ワールド>::生成する(0.0, 0.0, 0.0, 1.0) {
        Ok(値) => 値,
        Err(誤り) => panic!("床の恒等回転が検証を満たさない: {誤り}"),
    };
    変換::trsから生成する(中心, 回転, [床の水平倍率, 床の垂直倍率, 床の水平倍率])
}
