//! 個体が1体だけのインスタンス群を焼く入口。担当するのは「どの配置で焼くか」の選択だけであり、
//! 群と床の組み立ては`floor_scene`が行う。
//!
//! 個体が1体だけの描画対象は、専用のストレージバッファを確保せず描画対象ユニフォームの先頭112バイトを
//! 個体変換1件として読む。この配置が実機で正しいことは、恒等でない変換を1体へ与えて初めて画素に現れる。
//! 平行移動・回転・非一様スケールをすべて含めるのはそのためであり、どれか1つでも欠けると先頭の配置が
//! 崩れても同じ絵になりうる。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「描画発行」

use blitz_engine::{アセットID, カタログ, チャンク座標, 個体配置};

use super::floor_scene;
use crate::compile::コンパイル済みシーン;
use crate::error::アセットコンパイルエラー;

/// チャンク中央の東側。ここに立てると、ほぼ水平の方向光が作る影が中央の床を横切り、個体と影の両方が画面に入る。
const 平行移動: [f32; 3] = [62.0, 0.0, 50.0];

/// Y軸まわり40度の回転。クォータニオンは半角20度の正弦と余弦である。
/// 恒等でも90度の倍数でもない角にするのは、軸の入れ替えでたまたま一致する変換を避けるためである。
const 回転: [f32; 4] = [0.0, 0.342_020_14, 0.0, 0.939_692_6];

/// 3軸で異なる倍率。高さ3メートルの原型が9メートルになり、影が床を長く横切る。
const スケール: [f32; 3] = [2.0, 3.0, 0.6];

pub fn 植生単一個体シーンをコンパイルする(
    カタログ: &カタログ,
    id: &アセットID,
    所有チャンク: チャンク座標,
) -> Result<コンパイル済みシーン, アセットコンパイルエラー> {
    let 配置一覧 = vec![個体配置::生成する(平行移動, 回転, スケール)?];
    floor_scene::群と床のシーンをコンパイルする(カタログ, id, 所有チャンク, 配置一覧)
}
