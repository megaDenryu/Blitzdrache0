//! 個体別LODの検収に使う固定配置。受け取る値は無く、返すのはチャンクの基準原点からの相対の配置列である。
//! 個体をカメラからの等距離の弧へ並べ、弧ごとに狙った距離を持たせる。距離が段を決めるため、
//! 弧ごとに段が決まり、1つの群の中で複数の段が同時に非零になる。
//!
//! 座標は`crates/blitz_app/src/app/scene_camera.rs`の植生シーンの初期カメラを前提に固定している。
//! そのカメラは注視点(50, 0, 50)を距離45メートル・見下ろし60度から見るため、視点は(50, 38.9711, 72.5)にある。
//! 個体の境界球の中心は原型の高さ3メートルの半分にあたる高さ1.5メートルであり、視点との高さ差は37.4711メートルになる。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「段階導入」

use blitz_engine::個体配置;

use crate::error::アセットコンパイルエラー;

/// 視点と個体の境界球中心の高さ差。この距離はどの個体でも共通のため、弧の半径から水平の奥行きを解ける。
const 高さ差メートル: f32 = 37.4711;

/// 視点の水平位置。チャンク中央(50, 50)から手前へ22.5メートル退いた点である。
const 視点の水平位置: f32 = 50.0;
const 視点の奥行き位置: f32 = 72.5;

/// 弧ごとの狙った距離。基準距離50メートルに対し、40・45・48.5は段0、60・68は段1へ落ちる。
/// 48.5をヒステリシス帯の内側へ置くのは、カメラを数メートル動かすと境界50メートルをまたぐ弧を1つ用意し、
/// 帯の内側の往復で段が振動しないことを検収で見るためである。
const 弧の距離一覧: [f32; 5] = [40.0, 45.0, 48.5, 60.0, 68.0];

/// 弧の上に並べる横方向のずれ。個体が画面上で重ならない幅であり、同じ弧の3体は距離が等しい。
const 横のずれ一覧: [f32; 3] = [-12.0, 0.0, 12.0];

const 恒等回転: [f32; 4] = [0.0, 0.0, 0.0, 1.0];

pub(super) fn 配置列を作る() -> Result<Vec<個体配置>, アセットコンパイルエラー> {
    let mut 配置一覧 = Vec::with_capacity(弧の距離一覧.len() * 横のずれ一覧.len());
    for 距離 in 弧の距離一覧 {
        for 横のずれ in 横のずれ一覧 {
            let 奥行き = 奥行きを解く(距離, 横のずれ)?;
            配置一覧.push(個体配置::生成する(
                [視点の水平位置 + 横のずれ, 0.0, 視点の奥行き位置 - 奥行き],
                恒等回転,
                [1.0; 3],
            )?);
        }
    }
    Ok(配置一覧)
}

/// 視点から狙った距離になる、視点より奥側の水平距離。高さ差と横のずれを引いた残りの平方根である。
/// 残りが正でない距離は視点の真下より近いことを意味し、配置として成立しないため型付きエラーで拒む。
fn 奥行きを解く(距離: f32, 横のずれ: f32) -> Result<f32, アセットコンパイルエラー> {
    let 残り = 距離 * 距離 - 高さ差メートル * 高さ差メートル - 横のずれ * 横のずれ;
    if 残り <= 0.0 {
        return Err(アセットコンパイルエラー::植生詳細段弧の距離不足(距離));
    }
    Ok(残り.sqrt())
}
