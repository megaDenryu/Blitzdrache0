//! 可視判定の検収に使う固定配置。受け取る値は無く、返すのはチャンクの基準原点からの相対の配置列である。
//! 格子状の配置と違い、可視・視錐台外の番兵・画面外から画面内へ影を落とす個体の3種を意図した位置へ1体ずつ置く。
//! 座標は`crates/blitz_app/src/app/scene_camera.rs`の植生シーンの初期カメラと
//! `crates/blitz_app/src/app/scene_lighting.rs`の検収用ライト方針を前提に固定している。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「段階導入」

use blitz_engine::個体配置;

use crate::error::アセットコンパイルエラー;

/// カメラの視錐台に必ず入る4体。チャンク中央の(50, 50)を囲む位置に置く。
const 可視個体の平行移動: [[f32; 3]; 4] = [[44.0, 0.0, 44.0], [56.0, 0.0, 44.0], [44.0, 0.0, 56.0], [56.0, 0.0, 56.0]];

/// 視錐台の外に置く番兵。可視判定が効けば描かれず、効かなければ画素に現れる。
/// 影の正射影範囲の外でもあるため、この個体は影も落とさない。
const 番兵の平行移動: [f32; 3] = [-300.0, 0.0, 50.0];

/// カメラの視錐台の外にありながら、ほぼ水平の方向光で画面内の床へ影を落とす個体。
/// 倍率12は高さ36メートルに当たり、影の先端が画面中央付近の床へ届く。
const 影投げの平行移動: [f32; 3] = [150.0, 0.0, 50.0];
const 影投げの倍率: f32 = 12.0;

const 恒等回転: [f32; 4] = [0.0, 0.0, 0.0, 1.0];

pub(super) fn 配置列を作る() -> Result<Vec<個体配置>, アセットコンパイルエラー> {
    let mut 配置一覧 = Vec::with_capacity(可視個体の平行移動.len() + 2);
    for 平行移動 in 可視個体の平行移動 {
        配置一覧.push(個体配置::生成する(平行移動, 恒等回転, [1.0; 3])?);
    }
    配置一覧.push(個体配置::生成する(番兵の平行移動, 恒等回転, [1.0; 3])?);
    配置一覧.push(個体配置::生成する(影投げの平行移動, 恒等回転, [影投げの倍率; 3])?);
    Ok(配置一覧)
}
