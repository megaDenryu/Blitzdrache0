//! 地表の面: 最詳細段が張る三角形の平面を、1点での高さと2方向の傾きとして読んだ値。
//! 触れるのはこの3つの数だけであり、どの三角形から来たかも格子の刻みも知らない。
//!
//! 傾きを角度でなく「1メートル進むときに何メートル上がるか」で持つのは、逆三角関数を通さないためである。
//! 法線もここで正規化まで済ませて返すのは、法線の作り方(高さの勾配から作ること)がこの平面の性質であり、
//! 使う側ごとに組み立てると符号の取り違えが2箇所へ散るためである。

/// 局所座標の1点での地表の平面。東はローカルのX、南はローカルのZである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 地表の面 {
    高さメートル: f32,
    東の傾き: f32,
    南の傾き: f32,
}

impl 地表の面 {
    pub(crate) fn 生成する(高さメートル: f32, 東の傾き: f32, 南の傾き: f32) -> Self {
        Self {
            高さメートル,
            東の傾き,
            南の傾き,
        }
    }

    pub(crate) fn 高さメートル(&self) -> f32 {
        self.高さメートル
    }

    /// 傾きの大きさの二乗。平方根を通さないのは、散布の受け入れの判定が閾値の二乗と比べるだけで済むためである。
    pub(crate) fn 傾きの大きさの二乗(&self) -> f32 {
        self.東の傾き * self.東の傾き + self.南の傾き * self.南の傾き
    }

    /// 長さ1に正した地表の法線。高さの勾配が(東の傾き, 南の傾き)である平面の法線は、正規化する前は
    /// (-東の傾き, 1, -南の傾き)である。平方根は仕様が結果を1つに定めるため、機材が変わっても同じビット列になる。
    pub(crate) fn 正した法線(&self) -> [f32; 3] {
        let 正す前 = [-self.東の傾き, 1.0, -self.南の傾き];
        let 長さ = (正す前[0] * 正す前[0] + 正す前[1] * 正す前[1] + 正す前[2] * 正す前[2]).sqrt();
        [正す前[0] / 長さ, 正す前[1] / 長さ, 正す前[2] / 長さ]
    }
}
