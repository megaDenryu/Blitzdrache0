//! 地形メッシュの構造検査。決定性・隣接チャンクの境界整合・スカートの構造の3つを、コンパイラが焼いた実行時シーンそのもので確かめる。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「DoDの検査設計」

#![allow(clippy::unwrap_used)]

use std::path::PathBuf;

use blitz_engine::{シーンを実行時形式へ格納する, シーンデータ, チャンク座標, メッシュ頂点属性};

use crate::height_grid::{高さ格子を切り出す, 高さ格子諸元};

use super::{surface, スカート深さメートル};

const 検査用辺分割数: u16 = 8;
const 検査用一辺メートル: f32 = 100.0;

/// 大域サンプル添字だけから決まる高さ。隣接チャンクが共有する標本を同じ添字で引くため、境界整合の前提を再現できる。
fn 検査用の高さ(添字x: i16, 添字z: i16) -> f32 {
    let x = f32::from(添字x);
    let z = f32::from(添字z);
    (x / 5.0).sin() * 3.0 + (z / 7.0).cos() * 2.0 + x * 0.05
}

fn シーンを焼く(チャンク: チャンク座標) -> シーンデータ {
    let 諸元 = 高さ格子諸元::生成する(検査用辺分割数, 1, 検査用一辺メートル).unwrap();
    let 格子 = 高さ格子を切り出す(諸元, チャンク, 検査用の高さ).unwrap();
    super::シーンを組み立てる(&格子, チャンク, PathBuf::from("検査用")).unwrap()
}

fn 頂点一覧を取り出す(シーン: &シーンデータ) -> Vec<メッシュ頂点属性> {
    シーン.先頭の描画対象().形状().最詳細メッシュ().頂点一覧.clone()
}

fn 表面頂点数() -> usize {
    let 辺 = usize::from(検査用辺分割数) + 1;
    辺 * 辺
}

#[test]
fn 同じ格子から二度焼いた実行時バイト列が一致する() {
    let 座標 = チャンク座標::生成する(1, -2);
    let 一回目 = シーンを実行時形式へ格納する(&シーンを焼く(座標)).unwrap();
    let 二回目 = シーンを実行時形式へ格納する(&シーンを焼く(座標)).unwrap();
    assert_eq!(一回目, 二回目);
}

#[test]
fn 隣接チャンクの共有辺で高さと法線が一致する() {
    let 諸元 = 高さ格子諸元::生成する(検査用辺分割数, 1, 検査用一辺メートル).unwrap();
    let 分割数 = i32::from(検査用辺分割数);
    let 左 = 頂点一覧を取り出す(&シーンを焼く(チャンク座標::生成する(0, 0)));
    let 右 = 頂点一覧を取り出す(&シーンを焼く(チャンク座標::生成する(1, 0)));
    for 格子添字z in 0..=分割数 {
        let 左端 = usize::try_from(surface::頂点添字を求める(諸元, 分割数, 格子添字z).unwrap()).unwrap();
        let 右端 = usize::try_from(surface::頂点添字を求める(諸元, 0, 格子添字z).unwrap()).unwrap();
        assert_eq!(左[左端].位置[1], 右[右端].位置[1], "Z={格子添字z}の共有頂点の高さ");
        assert_eq!(左[左端].法線, 右[右端].法線, "Z={格子添字z}の共有頂点の法線");
        assert_eq!(左[左端].接線, 右[右端].接線, "Z={格子添字z}の共有頂点の接線");
    }
}

#[test]
fn スカート頂点は外周頂点を固定深さだけ下げた複製である() {
    let 頂点一覧 = 頂点一覧を取り出す(&シーンを焼く(チャンク座標::生成する(0, 0)));
    let 外周点数 = 4 * usize::from(検査用辺分割数);
    assert_eq!(頂点一覧.len(), 表面頂点数() + 外周点数);
    for 位置 in 0..外周点数 {
        let 下 = 頂点一覧[表面頂点数() + 位置];
        let 上 = 複製元を探す(&頂点一覧[..表面頂点数()], 下, 位置);
        assert!(外周にあるか(上), "スカート{位置}番の複製元が外周にない");
        assert_eq!(下.位置, [上.位置[0], 上.位置[1] - スカート深さメートル, 上.位置[2]]);
        assert_eq!(下.法線, 上.法線);
        assert_eq!(下.接線, 上.接線);
        assert_eq!(下.uv, 上.uv);
    }
}

/// スカート頂点はXZが複製元と同じであり、格子点のXZは重複しないため、XZの一致だけで複製元が定まる。
fn 複製元を探す(
    表面頂点一覧: &[メッシュ頂点属性], スカート頂点: メッシュ頂点属性, 位置: usize
) -> メッシュ頂点属性 {
    let 見つけた = 表面頂点一覧
        .iter()
        .find(|頂点| 頂点.位置[0] == スカート頂点.位置[0] && 頂点.位置[2] == スカート頂点.位置[2]);
    match 見つけた {
        Some(頂点) => *頂点,
        None => panic!("スカート{位置}番の複製元が表面に無い"),
    }
}

fn 外周にあるか(頂点: メッシュ頂点属性) -> bool {
    let 端 = 検査用一辺メートル;
    頂点.位置[0] == 0.0 || 頂点.位置[0] == 端 || 頂点.位置[2] == 0.0 || 頂点.位置[2] == 端
}
