//! 格子点1つ分の頂点を作る工程。受け取るのは高さ格子と格子添字、返すのは位置・法線・接線・UVを備えた頂点である。
//! 位置はチャンク原点を基準にした局所メートルであり、世界のどこに置かれるかは描画アンカーが決めるためここでは扱わない。
//! 法線と接線は隣接標本の中央差分から求める。差分が重なり領域の標本だけで閉じるため、境界の格子点でも隣接チャンクと同じ値になる。

use blitz_engine::メッシュ頂点属性;

use crate::height_grid::{高さ格子, 高さ格子エラー};

pub(super) fn 格子点の頂点を作る(
    格子: &高さ格子,
    格子添字x: i32,
    格子添字z: i32,
) -> Result<メッシュ頂点属性, 高さ格子エラー> {
    let 諸元 = 格子.諸元();
    let 刻み = 諸元.刻みメートル();
    let 高さ = 格子.高さ(格子添字x, 格子添字z)?;
    let 傾きx = (格子.高さ(格子添字x + 1, 格子添字z)? - 格子.高さ(格子添字x - 1, 格子添字z)?) / (2.0 * 刻み);
    let 傾きz = (格子.高さ(格子添字x, 格子添字z + 1)? - 格子.高さ(格子添字x, 格子添字z - 1)?) / (2.0 * 刻み);
    let (実数x, 実数z) = 格子添字を実数へ変換する(格子添字x, 格子添字z)?;
    let 分割 = f32::from(諸元.辺分割数());
    Ok(メッシュ頂点属性 {
        位置: [実数x * 刻み, 高さ, 実数z * 刻み],
        法線: 正規化する([-傾きx, 1.0, -傾きz]),
        接線: 接線を作る(傾きx),
        // Vのプラスをワールドの-Zへ向けるのは、板の世界と同じ構図にして接線のw=+1を幾何学的に正しい値に保つためである。
        uv: [実数x / 分割, 1.0 - 実数z / 分割],
    })
}

/// UのプラスがワールドのXに沿うため、接線はX方向の面上ベクトルになる。w=+1で従法線がVのプラス方向を向く。
fn 接線を作る(傾きx: f32) -> [f32; 4] {
    let 方向 = 正規化する([1.0, 傾きx, 0.0]);
    [方向[0], 方向[1], 方向[2], 1.0]
}

/// 注意: 呼び出し側が渡すベクトルはY成分かX成分が1であり、長さは常に1以上になる。0除算は起きない。
fn 正規化する(ベクトル: [f32; 3]) -> [f32; 3] {
    let 長さ = (ベクトル[0] * ベクトル[0] + ベクトル[1] * ベクトル[1] + ベクトル[2] * ベクトル[2]).sqrt();
    [ベクトル[0] / 長さ, ベクトル[1] / 長さ, ベクトル[2] / 長さ]
}

/// 位置とUVを求めるための実数化。値を落とさずf32へ変換できるのはi16の範囲だけであるため、超える添字は型付きエラーにする。
fn 格子添字を実数へ変換する(格子添字x: i32, 格子添字z: i32) -> Result<(f32, f32), 高さ格子エラー> {
    let 狭めたx = i16::try_from(格子添字x).map_err(|_| 高さ格子エラー::格子添字範囲外 {
        x: 格子添字x, z: 格子添字z
    })?;
    let 狭めたz = i16::try_from(格子添字z).map_err(|_| 高さ格子エラー::格子添字範囲外 {
        x: 格子添字x, z: 格子添字z
    })?;
    Ok((f32::from(狭めたx), f32::from(狭めたz)))
}
