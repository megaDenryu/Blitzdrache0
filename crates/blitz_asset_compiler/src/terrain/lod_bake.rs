//! 詳細段ごとのメッシュを焼く工程。受け取るのは高さ格子、返すのは段番号順に並んだ地形LODメッシュ群である。
//! 何段を焼くか、段ごとの格子をどう間引くか、スカートをどれだけ下げるかはこの工程の中で閉じており、呼び出し元は結果の群だけを受け取る。

use blitz_engine::{メッシュデータ, 地形LODメッシュ群};

use crate::height_grid::{高さ格子, 高さ格子エラー};

use super::lod_level::地形段諸元;
use super::{skirt, skirt_depth, surface};

/// スカートの深さはチャンクごとに1つ求め、全段へ同じ値を適用する。段ごとに変えると、同じ継ぎ目を挟む2段が違う深さで垂れ下がり、深い側の帯が浅い側からはみ出して見えるためである。
pub(super) fn 段別メッシュを焼く(格子: &高さ格子) -> Result<地形LODメッシュ群, 高さ格子エラー> {
    let 段一覧 = 地形段諸元::段一覧を作る(格子.諸元());
    let 深さメートル = skirt_depth::スカート深さを求める(格子, &段一覧)?;
    let Some((最詳細段諸元, より粗い段諸元一覧)) = 段一覧.split_first() else {
        panic!("段一覧は1段以上を持つ不変条件に違反した");
    };
    let 最詳細段 = 段のメッシュを焼く(格子, *最詳細段諸元, 深さメートル)?;
    let mut より粗い段一覧 = Vec::with_capacity(より粗い段諸元一覧.len());
    for 段諸元 in より粗い段諸元一覧 {
        より粗い段一覧.push(段のメッシュを焼く(格子, *段諸元, 深さメートル)?);
    }
    Ok(地形LODメッシュ群::生成する(最詳細段, より粗い段一覧))
}

fn 段のメッシュを焼く(
    格子: &高さ格子, 段諸元: 地形段諸元, 深さメートル: f32
) -> Result<メッシュデータ, 高さ格子エラー> {
    let mut 組み立て = surface::表面を組み立てる(格子, 段諸元)?;
    skirt::スカートを積む(&mut 組み立て, 段諸元, 深さメートル)?;
    Ok(メッシュデータ {
        頂点一覧: 組み立て.頂点一覧,
        インデックス一覧: 組み立て.インデックス一覧,
        スキン頂点属性一覧: None,
    })
}
