//! 外周スカートを積む工程。受け取るのは組み立て途中の地形メッシュと段の諸元、加えるのは外周の格子点を規定深さだけ下げた複製頂点と、外周を1周する帯の三角形である。
//! 外周の走査は南辺(Zが最小)を+X、東辺を+Z、北辺を-X、西辺を-Zの順に1周する固定順であり、帯の三角形は常に外向きが表になる。
//! 下げた頂点は法線・接線・UVを複製元から変えない。継ぎ目が露出したときに、覗いた面が地表と同じ陰影で見えるためである。

use crate::height_grid::高さ格子エラー;

use super::lod_level::地形段諸元;
use super::surface::{地形メッシュ組み立て, 頂点添字を求める};

pub(super) fn スカートを積む(
    組み立て: &mut 地形メッシュ組み立て, 段諸元: 地形段諸元, 深さメートル: f32
) -> Result<(), 高さ格子エラー> {
    let 上辺一覧 = 外周の頂点添字一覧(段諸元)?;
    let 下辺一覧 = 下げた複製を積む(組み立て, &上辺一覧, 深さメートル)?;
    帯の三角形を並べる(組み立て, &上辺一覧, &下辺一覧);
    Ok(())
}

fn 下げた複製を積む(
    組み立て: &mut 地形メッシュ組み立て, 上辺一覧: &[u32], 深さメートル: f32
) -> Result<Vec<u32>, 高さ格子エラー> {
    let mut 下辺一覧 = Vec::with_capacity(上辺一覧.len());
    for 上辺添字 in 上辺一覧 {
        let 元位置 = usize::try_from(*上辺添字).map_err(|_| 高さ格子エラー::頂点数表現不能(上辺一覧.len()))?;
        let mut 頂点 = *組み立て.頂点一覧.get(元位置).ok_or(高さ格子エラー::頂点数表現不能(元位置))?;
        頂点.位置[1] -= 深さメートル;
        let 追加位置 = 組み立て.頂点一覧.len();
        下辺一覧.push(u32::try_from(追加位置).map_err(|_| 高さ格子エラー::頂点数表現不能(追加位置))?);
        組み立て.頂点一覧.push(頂点);
    }
    Ok(下辺一覧)
}

/// 帯を1周ぶん張る。最後の辺は先頭へ戻って閉じるため、外周に切れ目は生じない。
fn 帯の三角形を並べる(組み立て: &mut 地形メッシュ組み立て, 上辺一覧: &[u32], 下辺一覧: &[u32]) {
    let 周回数 = 上辺一覧.len();
    for 位置 in 0..周回数 {
        let 次 = (位置 + 1) % 周回数;
        let (Some(上手前), Some(上次), Some(下手前), Some(下次)) = (上辺一覧.get(位置), 上辺一覧.get(次), 下辺一覧.get(位置), 下辺一覧.get(次))
        else {
            continue;
        };
        組み立て
            .インデックス一覧
            .extend_from_slice(&[*上手前, *上次, *下次, *上手前, *下次, *下手前]);
    }
}

/// 外周の格子点を1周ぶん、表面頂点の並び順での位置として返す。角の格子点は1度だけ現れる。
fn 外周の頂点添字一覧(段諸元: 地形段諸元) -> Result<Vec<u32>, 高さ格子エラー> {
    let 分割数 = 段諸元.辺分割数();
    let mut 一覧 = Vec::new();
    for 格子添字x in 0..=分割数 {
        一覧.push(頂点添字を求める(段諸元, 格子添字x, 0)?);
    }
    for 格子添字z in 1..=分割数 {
        一覧.push(頂点添字を求める(段諸元, 分割数, 格子添字z)?);
    }
    for 格子添字x in (0..分割数).rev() {
        一覧.push(頂点添字を求める(段諸元, 格子添字x, 分割数)?);
    }
    for 格子添字z in (1..分割数).rev() {
        一覧.push(頂点添字を求める(段諸元, 0, 格子添字z)?);
    }
    Ok(一覧)
}
