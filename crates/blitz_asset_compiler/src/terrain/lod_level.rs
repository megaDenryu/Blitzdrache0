//! 詳細段1つが高さ格子をどう間引くかの諸元。受け取るのは高さ格子の諸元、返すのは段番号順の諸元一覧である。
//! 辺分割数を段ごとに半減させるため、粗い段の格子点は必ず細かい段の格子点の部分集合になる。標本刻みはそのまま高さ格子の格子添字の刻みでもある。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「LOD」

use crate::height_grid::{高さ格子エラー, 高さ格子諸元};

/// 焼く段数の上限。5段で辺分割数は64から4まで下がり、最も粗い段の頂点数は最詳細段の256分の1になる。
const 最大段数: usize = 5;

/// 最も粗い段に許す辺分割数の下限。これを下回るとチャンクの四隅と辺の中点だけになり、外周スカートの帯が塞ぐ隙間より起伏の欠落が大きくなる。
const 最小辺分割数: u16 = 4;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 地形段諸元 {
    辺分割数: u16,
    標本刻み: i32,
}

impl 地形段諸元 {
    /// 段番号の昇順に並んだ諸元。先頭は高さ格子の辺分割数そのままの最詳細段であり、必ず1件以上を返す。
    pub(super) fn 段一覧を作る(格子諸元: 高さ格子諸元) -> Vec<Self> {
        let mut 一覧 = Vec::with_capacity(最大段数);
        let mut 辺分割数 = 格子諸元.辺分割数();
        let mut 標本刻み = 1;
        while 一覧.len() < 最大段数 {
            一覧.push(Self { 辺分割数, 標本刻み });
            if 辺分割数 <= 最小辺分割数 {
                break;
            }
            辺分割数 /= 2;
            標本刻み *= 2;
        }
        一覧
    }

    pub(super) fn 辺分割数(self) -> i32 {
        i32::from(self.辺分割数)
    }

    /// この段の格子点1つ進むあいだに高さ格子の格子添字が進む数。
    pub(super) fn 標本刻み(self) -> i32 {
        self.標本刻み
    }

    /// この段の1辺の格子点数。
    pub(super) fn 格子点数(self) -> Result<i32, 高さ格子エラー> {
        self.辺分割数().checked_add(1).ok_or(高さ格子エラー::格子添字範囲外 {
            x: self.辺分割数(),
            z: self.辺分割数(),
        })
    }
}
