//! チャンク1つ分のスカート深さを求める工程。受け取るのは高さ格子と段番号順の諸元一覧、返すのは深さメートルである。
//! 四辺それぞれについて、隣り合う2段の辺のあいだで最も大きく開く隙間を求め、その全対の最大へ安全幅を足す。
//! 隣り合うチャンクの段差は最大1段へ緩和されるため、隣り合う段の対だけを見れば実際に開きうる隙間を必ず上回る。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「スカートの深さ」

use crate::height_grid::{高さ格子, 高さ格子エラー};

use super::lod_level::地形段諸元;

/// 最大偏差へ足す余裕。標本の位置が完全に一致しても浮動小数の丸めで僅かに開くため、0では隙間が残りうる。
const 安全幅メートル: f32 = 0.5;

/// 深さを求める対象の辺。四辺のうちどれを走るかで固定する軸と動かす軸が入れ替わる。
#[derive(Debug, Clone, Copy)]
enum 辺 {
    南,
    北,
    西,
    東,
}

const 全ての辺: [辺; 4] = [辺::南, 辺::北, 辺::西, 辺::東];

pub(super) fn スカート深さを求める(格子: &高さ格子, 段一覧: &[地形段諸元]) -> Result<f32, 高さ格子エラー> {
    let 分割数 = i32::from(格子.諸元().辺分割数());
    let mut 最大偏差 = 0.0_f32;
    for 対 in 段一覧.windows(2) {
        let [細かい段, _] = 対 else {
            continue;
        };
        for 辺 in 全ての辺 {
            最大偏差 = 最大偏差.max(辺の最大偏差(格子, 辺, 分割数, 細かい段.標本刻み())?);
        }
    }
    Ok(最大偏差 + 安全幅メートル)
}

/// 細かい段の格子点が、1段粗い辺を結んだ直線からどれだけ離れるかの最大値。粗い段の格子点は細かい段の格子点の部分集合であるため、
/// 粗い辺は細かい段の格子点を1つおきに結んだ折れ線である。
fn 辺の最大偏差(格子: &高さ格子, 辺: 辺, 分割数: i32, 細刻み: i32) -> Result<f32, 高さ格子エラー> {
    let 粗刻み = 細刻み * 2;
    let mut 最大 = 0.0_f32;
    let mut 位置 = 0;
    while 位置 <= 分割数 {
        let 手前 = (位置 / 粗刻み) * 粗刻み;
        if 手前 < 分割数 {
            let 奥 = 手前 + 粗刻み;
            let 比率 = f32から求める(位置 - 手前)? / f32から求める(粗刻み)?;
            let 補間 = 辺の高さ(格子, 辺, 手前, 分割数)? * (1.0 - 比率) + 辺の高さ(格子, 辺, 奥, 分割数)? * 比率;
            最大 = 最大.max((辺の高さ(格子, 辺, 位置, 分割数)? - 補間).abs());
        }
        位置 += 細刻み;
    }
    Ok(最大)
}

fn 辺の高さ(格子: &高さ格子, 辺: 辺, 位置: i32, 分割数: i32) -> Result<f32, 高さ格子エラー> {
    match 辺 {
        辺::南 => 格子.高さ(位置, 0),
        辺::北 => 格子.高さ(位置, 分割数),
        辺::西 => 格子.高さ(0, 位置),
        辺::東 => 格子.高さ(分割数, 位置),
    }
}

/// 格子添字を実数へ変換する。値を落とさずf32へ変換できるのはi16の範囲だけであるため、超える値は型付きエラーにする。
fn f32から求める(値: i32) -> Result<f32, 高さ格子エラー> {
    let 狭めた = i16::try_from(値).map_err(|_| 高さ格子エラー::格子添字範囲外 { x: 値, z: 値 })?;
    Ok(f32::from(狭めた))
}
