//! 1つの詳細段の格子面を組み立てる工程。受け取るのは高さ格子と段の諸元、返すのは格子点順の頂点一覧と三角形一覧である。
//! 走査順はZを外側・Xを内側の昇順に固定し、四角形の対角は常に(X,Z)から(X+1,Z+1)へ張る。この2つを固定するため、同じ格子と同じ段からは常に同じ並びを得る。
//! 三角形の頂点順は面の表がYのプラス側を向く向きで揃える。

use blitz_engine::メッシュ頂点属性;

use crate::height_grid::{高さ格子, 高さ格子エラー};

use super::lod_level::地形段諸元;
use super::vertex;

/// 組み立て途中の地形メッシュ。スカートを積む工程がこの続きへ頂点と三角形を足す。
pub(super) struct 地形メッシュ組み立て {
    pub(super) 頂点一覧: Vec<メッシュ頂点属性>,
    pub(super) インデックス一覧: Vec<u32>,
}

pub(super) fn 表面を組み立てる(
    格子: &高さ格子, 段諸元: 地形段諸元
) -> Result<地形メッシュ組み立て, 高さ格子エラー> {
    let 分割数 = 段諸元.辺分割数();
    let 刻み = 段諸元.標本刻み();
    let mut 頂点一覧 = Vec::new();
    for 格子添字z in 0..=分割数 {
        for 格子添字x in 0..=分割数 {
            頂点一覧.push(vertex::格子点の頂点を作る(格子, 格子添字x * 刻み, 格子添字z * 刻み)?);
        }
    }
    Ok(地形メッシュ組み立て {
        頂点一覧,
        インデックス一覧: 三角形を並べる(段諸元)?,
    })
}

fn 三角形を並べる(段諸元: 地形段諸元) -> Result<Vec<u32>, 高さ格子エラー> {
    let 分割数 = 段諸元.辺分割数();
    let mut インデックス一覧 = Vec::new();
    for 格子添字z in 0..分割数 {
        for 格子添字x in 0..分割数 {
            let 手前左 = 頂点添字を求める(段諸元, 格子添字x, 格子添字z)?;
            let 奥左 = 頂点添字を求める(段諸元, 格子添字x, 格子添字z + 1)?;
            let 奥右 = 頂点添字を求める(段諸元, 格子添字x + 1, 格子添字z + 1)?;
            let 手前右 = 頂点添字を求める(段諸元, 格子添字x + 1, 格子添字z)?;
            インデックス一覧.extend_from_slice(&[手前左, 奥左, 奥右, 手前左, 奥右, 手前右]);
        }
    }
    Ok(インデックス一覧)
}

/// 段の格子添字から表面頂点の並び順での位置を求める。スカートの工程も外周の頂点を指すためにこれを使う。
pub(super) fn 頂点添字を求める(段諸元: 地形段諸元, 格子添字x: i32, 格子添字z: i32) -> Result<u32, 高さ格子エラー> {
    let 範囲外 = || 高さ格子エラー::格子添字範囲外 {
        x: 格子添字x, z: 格子添字z
    };
    let 分割数 = 段諸元.辺分割数();
    if 格子添字x < 0 || 格子添字x > 分割数 || 格子添字z < 0 || 格子添字z > 分割数 {
        return Err(範囲外());
    }
    let 格子点数 = 段諸元.格子点数()?;
    u32::try_from(格子添字z * 格子点数 + 格子添字x).map_err(|_| 範囲外())
}
