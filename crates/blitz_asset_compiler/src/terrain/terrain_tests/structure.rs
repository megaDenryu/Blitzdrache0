//! 決定性と段構成の検査。同じ格子から同じバイト列を得ること、段の辺分割数が半減して並ぶこと、段ごとの頂点数と三角形数が辺分割数から決まることを確かめる。

use blitz_engine::{シーンを実行時形式へ格納する, チャンク座標};

use super::fixture::{シーンを焼く, 検査用辺分割数, 段一覧, 段別メッシュを取り出す, 表面頂点数};

#[test]
fn 同じ格子から二度焼いた実行時バイト列が一致する() {
    let 座標 = チャンク座標::生成する(1, -2);
    let 一回目 = シーンを実行時形式へ格納する(&シーンを焼く(座標)).unwrap();
    let 二回目 = シーンを実行時形式へ格納する(&シーンを焼く(座標)).unwrap();
    assert_eq!(一回目, 二回目);
}

#[test]
fn 段は辺分割数を半減させながら並ぶ() {
    let 一覧 = 段一覧();
    assert_eq!(一覧.len(), 3, "辺分割数16の段一覧は16・8・4の3段になる");
    for (段番号, 段諸元) in 一覧.iter().enumerate() {
        let 期待分割数 = i32::from(検査用辺分割数) >> 段番号;
        assert_eq!(段諸元.辺分割数(), 期待分割数, "段{段番号}の辺分割数");
        assert_eq!(段諸元.標本刻み(), 1 << 段番号, "段{段番号}の標本刻み");
    }
}

#[test]
fn 段ごとの頂点数と三角形数が辺分割数から決まる() {
    let メッシュ一覧 = 段別メッシュを取り出す(&シーンを焼く(チャンク座標::生成する(0, 0)));
    let 一覧 = 段一覧();
    assert_eq!(メッシュ一覧.len(), 一覧.len());
    for (段諸元, メッシュ) in 一覧.iter().zip(&メッシュ一覧) {
        let 分割数 = usize::try_from(段諸元.辺分割数()).unwrap();
        let 外周点数 = 4 * 分割数;
        assert_eq!(メッシュ.頂点一覧.len(), 表面頂点数(*段諸元) + 外周点数, "辺分割数{分割数}の頂点数");
        let 期待三角形数 = 分割数 * 分割数 * 2 + 外周点数 * 2;
        assert_eq!(メッシュ.インデックス一覧.len(), 期待三角形数 * 3, "辺分割数{分割数}の三角形数");
    }
}
