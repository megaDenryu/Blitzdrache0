//! 辺の整合の検査。隣接チャンクの共有辺が全段で一致すること、粗い段の辺の頂点が細かい段の辺の頂点の部分集合であることを確かめる。

use blitz_engine::チャンク座標;

use super::super::surface::頂点添字を求める;
use super::fixture::{段の頂点一覧, 段一覧};

#[test]
fn 隣接チャンクの共有辺で高さと法線が全段一致する() {
    for (段番号, 段諸元) in 段一覧().iter().enumerate() {
        let 分割数 = 段諸元.辺分割数();
        let 左 = 段の頂点一覧(チャンク座標::生成する(0, 0), 段番号);
        let 右 = 段の頂点一覧(チャンク座標::生成する(1, 0), 段番号);
        let 手前 = 段の頂点一覧(チャンク座標::生成する(0, 0), 段番号);
        let 奥 = 段の頂点一覧(チャンク座標::生成する(0, 1), 段番号);
        for 格子添字z in 0..=分割数 {
            let 左端 = usize::try_from(頂点添字を求める(*段諸元, 分割数, 格子添字z).unwrap()).unwrap();
            let 右端 = usize::try_from(頂点添字を求める(*段諸元, 0, 格子添字z).unwrap()).unwrap();
            assert_eq!(左[左端].位置[1], 右[右端].位置[1], "段{段番号}のZ={格子添字z}の共有頂点の高さ");
            assert_eq!(左[左端].法線, 右[右端].法線, "段{段番号}のZ={格子添字z}の共有頂点の法線");
            assert_eq!(左[左端].接線, 右[右端].接線, "段{段番号}のZ={格子添字z}の共有頂点の接線");
            let 手前端 = usize::try_from(頂点添字を求める(*段諸元, 格子添字z, 分割数).unwrap()).unwrap();
            let 奥端 = usize::try_from(頂点添字を求める(*段諸元, 格子添字z, 0).unwrap()).unwrap();
            assert_eq!(手前[手前端].位置[1], 奥[奥端].位置[1], "段{段番号}のX={格子添字z}の共有頂点の高さ");
            assert_eq!(手前[手前端].法線, 奥[奥端].法線, "段{段番号}のX={格子添字z}の共有頂点の法線");
        }
    }
}

#[test]
fn 任意の粗い段の四辺は細かい段の辺の部分集合である() {
    let 一覧 = 段一覧();
    let 座標 = チャンク座標::生成する(-1, 2);
    for 細段番号 in 0..一覧.len() - 1 {
        for 粗段番号 in 細段番号 + 1..一覧.len() {
            let 細段 = 一覧[細段番号];
            let 粗段 = 一覧[粗段番号];
            let 比率 = 細段.辺分割数() / 粗段.辺分割数();
            let 細頂点 = 段の頂点一覧(座標, 細段番号);
            let 粗頂点 = 段の頂点一覧(座標, 粗段番号);
            for 粗添字 in 0..=粗段.辺分割数() {
                let 細添字 = 粗添字 * 比率;
                for (粗x, 粗z, 細x, 細z) in 四辺の添字(粗段.辺分割数(), 細段.辺分割数(), 粗添字, 細添字) {
                    assert_eq!(
                        位置を引く(&粗頂点, 粗段, 粗x, 粗z),
                        位置を引く(&細頂点, 細段, 細x, 細z),
                        "段{細段番号}と段{粗段番号}の辺"
                    );
                }
            }
        }
    }
}

fn 四辺の添字(粗端: i32, 細端: i32, 粗: i32, 細: i32) -> [(i32, i32, i32, i32); 4] {
    [(0, 粗, 0, 細), (粗端, 粗, 細端, 細), (粗, 0, 細, 0), (粗, 粗端, 細, 細端)]
}

fn 位置を引く(
    頂点一覧: &[blitz_engine::メッシュ頂点属性],
    段諸元: super::super::lod_level::地形段諸元,
    格子添字x: i32,
    格子添字z: i32,
) -> [f32; 3] {
    let 添字 = usize::try_from(頂点添字を求める(段諸元, 格子添字x, 格子添字z).unwrap()).unwrap();
    頂点一覧[添字].位置
}
