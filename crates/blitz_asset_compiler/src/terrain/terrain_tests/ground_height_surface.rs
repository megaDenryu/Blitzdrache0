//! 地表高さが最詳細段の実描画面と一致することの検査。担当するのは、焼いた表面の三角形一覧から点を覆う三角形を索き、
//! その三角形の平面上の高さを地表高さと突き合わせることである。対角の切り方を検査側に持たないため、
//! `surface`が対角の張り方を変えてもこの検査はその面へ追従する。

use blitz_engine::チャンク座標;

use crate::height_grid::高さ格子;
use crate::terrain::ground_height::地表高さを求める;
use crate::terrain::surface::{地形メッシュ組み立て, 表面を組み立てる};

use super::fixture::{検査用諸元, 検査用辺分割数, 段一覧, 鞍型格子を切り出す};

/// 三角形の面と突き合わせるときの許容差メートル。同じ平面を別の順序で評価したときのf32の丸めだけを許す幅である。
const 許容差メートル: f32 = 1.0e-4;

/// 双一次の値が面から外れたと数える差メートル。丸めの幅より2桁大きく取り、丸めを差と数えないようにする。
const 双一次との差の下限メートル: f32 = 1.0e-2;

/// 升目の内部で調べる比の組。対角(比x=比z)の両側と、対角に近い点を含める。
const 調べる比: [(f32, f32); 4] = [(0.25, 0.75), (0.75, 0.25), (0.4, 0.35), (0.1, 0.9)];

#[test]
fn 鞍型の升目の内部が実描画面の三角形と一致する() {
    let 格子 = 鞍型格子を切り出す(チャンク座標::生成する(0, 0));
    let 面 = 表面を組み立てる(&格子, 段一覧()[0]).unwrap();
    let 刻み = 検査用諸元().刻みメートル();
    let mut 双一次が外れた点数 = 0_u32;
    for 添字z in 0..検査用辺分割数 {
        for 添字x in 0..検査用辺分割数 {
            for (比x, 比z) in 調べる比 {
                let x = (f32::from(添字x) + 比x) * 刻み;
                let z = (f32::from(添字z) + 比z) * 刻み;
                let 実際 = 地表高さを求める(&格子, x, z).unwrap();
                let 期待 = 覆う三角形の高さ(&面, x, z);
                assert!((実際 - 期待).abs() <= 許容差メートル, "局所({x},{z})の{実際}が三角形の面の{期待}と違う");
                let 双一次 = 双一次の高さ(&格子, i32::from(添字x), i32::from(添字z), 比x, 比z);
                if (双一次 - 期待).abs() > 双一次との差の下限メートル {
                    双一次が外れた点数 += 1;
                }
            }
        }
    }
    assert!(
        双一次が外れた点数 > 0,
        "鞍型の格子で双一次が全点とも面に乗った。この検査は区分線形と双一次を見分けていない"
    );
}

/// 表面の三角形一覧から点をXZで覆う1つを索き、その平面上の高さを重心座標で求める。
/// 表面の三角形はXZへ射影しても面積を持つため、升目の内部の点は必ずどれかに覆われる。
fn 覆う三角形の高さ(面: &地形メッシュ組み立て, x: f32, z: f32) -> f32 {
    let 位置 = |添字: u32| 面.頂点一覧[usize::try_from(添字).unwrap()].位置;
    for 三角形 in 面.インデックス一覧.chunks_exact(3) {
        if let Some(高さ) = 三角形の平面の高さ([位置(三角形[0]), 位置(三角形[1]), 位置(三角形[2])], x, z) {
            return 高さ;
        }
    }
    panic!("局所({x},{z})を覆う三角形が表面に無い");
}

/// 点が三角形の内側にあればその平面上の高さ、外側なら値なし。辺の上を両側の三角形が拾えるよう、重心座標の下限を丸め幅だけ緩める。
fn 三角形の平面の高さ(頂点: [[f32; 3]; 3], x: f32, z: f32) -> Option<f32> {
    let [甲, 乙, 丙] = 頂点;
    let 面積の2倍 = (乙[2] - 丙[2]) * (甲[0] - 丙[0]) + (丙[0] - 乙[0]) * (甲[2] - 丙[2]);
    let 甲の重み = ((乙[2] - 丙[2]) * (x - 丙[0]) + (丙[0] - 乙[0]) * (z - 丙[2])) / 面積の2倍;
    let 乙の重み = ((丙[2] - 甲[2]) * (x - 丙[0]) + (甲[0] - 丙[0]) * (z - 丙[2])) / 面積の2倍;
    let 丙の重み = 1.0 - 甲の重み - 乙の重み;
    let 下限 = -1.0e-5;
    if 甲の重み < 下限 || 乙の重み < 下限 || 丙の重み < 下限 {
        return None;
    }
    Some(甲の重み * 甲[1] + 乙の重み * 乙[1] + 丙の重み * 丙[1])
}

/// 四隅の双一次補間。区分線形との差が見分けられる大きさであることを示すためだけに置く。
fn 双一次の高さ(格子: &高さ格子, 添字x: i32, 添字z: i32, 比x: f32, 比z: f32) -> f32 {
    let 混ぜる = |始: f32, 終: f32, 比: f32| 始 + (終 - 始) * 比;
    let 手前 = 混ぜる(格子.高さ(添字x, 添字z).unwrap(), 格子.高さ(添字x + 1, 添字z).unwrap(), 比x);
    let 奥 = 混ぜる(格子.高さ(添字x, 添字z + 1).unwrap(), 格子.高さ(添字x + 1, 添字z + 1).unwrap(), 比x);
    混ぜる(手前, 奥, 比z)
}
