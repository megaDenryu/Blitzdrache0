//! スカートの検査。全段のスカート頂点が外周頂点を同じ深さだけ下げた複製であること、深さが隣り合う段の辺の最大偏差に安全幅を足した値であることを確かめる。

use blitz_engine::{チャンク座標, メッシュ頂点属性};

use super::super::skirt_depth::スカート深さを求める;
use crate::height_grid::高さ格子;

use super::fixture::{格子を切り出す, 検査用一辺メートル, 検査用辺分割数, 段の頂点一覧, 段一覧, 表面頂点数};

#[test]
fn 全段のスカート頂点は外周頂点を同じ深さだけ下げた複製である() {
    let 座標 = チャンク座標::生成する(0, 0);
    let 深さ = スカート深さを求める(&格子を切り出す(座標), &段一覧()).unwrap();
    for (段番号, 段諸元) in 段一覧().iter().enumerate() {
        let 頂点一覧 = 段の頂点一覧(座標, 段番号);
        let 表面数 = 表面頂点数(*段諸元);
        let 外周点数 = 4 * usize::try_from(段諸元.辺分割数()).unwrap();
        assert_eq!(頂点一覧.len(), 表面数 + 外周点数, "段{段番号}の頂点数");
        for 位置 in 0..外周点数 {
            let 下 = 頂点一覧[表面数 + 位置];
            let 上 = 複製元を探す(&頂点一覧[..表面数], 下, 段番号, 位置);
            assert!(外周にあるか(上), "段{段番号}のスカート{位置}番の複製元が外周にない");
            assert_eq!(下.位置, [上.位置[0], 上.位置[1] - 深さ, 上.位置[2]]);
            assert_eq!(下.法線, 上.法線);
            assert_eq!(下.接線, 上.接線);
            assert_eq!(下.uv, 上.uv);
        }
    }
}

/// 深さの意味を検査側で組み直して照合する。実装が偏差の走査をやめて定数へ戻ったときに、この検査が落ちる。
#[test]
fn 深さは四辺と全段対の最大偏差に安全幅を足した値である() {
    let 格子 = 格子を切り出す(チャンク座標::生成する(1, -1));
    let 一覧 = 段一覧();
    let 深さ = スカート深さを求める(&格子, &一覧).unwrap();
    let 分割数 = i32::from(検査用辺分割数);
    let mut 最大偏差 = 0.0_f32;
    for 細かい段 in 一覧.iter().take(一覧.len() - 1) {
        let 細刻み = 細かい段.標本刻み();
        for 辺番号 in 0..4 {
            let mut 位置 = 0;
            while 位置 < 分割数 {
                let 手前 = (位置 / (細刻み * 2)) * (細刻み * 2);
                let 比率 = f32::from(i16::try_from(位置 - 手前).unwrap()) / f32::from(i16::try_from(細刻み * 2).unwrap());
                let 補間 = 辺の高さ(&格子, 辺番号, 手前, 分割数) * (1.0 - 比率) + 辺の高さ(&格子, 辺番号, 手前 + 細刻み * 2, 分割数) * 比率;
                最大偏差 = 最大偏差.max((辺の高さ(&格子, 辺番号, 位置, 分割数) - 補間).abs());
                位置 += 細刻み;
            }
        }
    }
    assert_eq!(深さ, 最大偏差 + 0.5);
    assert!(深さ < 12.0, "深さ{深さ}は第2段の固定値12メートルより小さい");
}

/// 検査用の辺の走査。実装の判別共用体と同じ4通りを、番号で並べ直したものである。
fn 辺の高さ(格子: &高さ格子, 辺番号: usize, 位置: i32, 分割数: i32) -> f32 {
    match 辺番号 {
        0 => 格子.高さ(位置, 0),
        1 => 格子.高さ(位置, 分割数),
        2 => 格子.高さ(0, 位置),
        _ => 格子.高さ(分割数, 位置),
    }
    .unwrap()
}

/// スカート頂点はXZが複製元と同じであり、格子点のXZは重複しないため、XZの一致だけで複製元が定まる。
fn 複製元を探す(
    表面頂点一覧: &[メッシュ頂点属性], スカート頂点: メッシュ頂点属性, 段番号: usize, 位置: usize
) -> メッシュ頂点属性 {
    let 見つけた = 表面頂点一覧
        .iter()
        .find(|頂点| 頂点.位置[0] == スカート頂点.位置[0] && 頂点.位置[2] == スカート頂点.位置[2]);
    match 見つけた {
        Some(頂点) => *頂点,
        None => panic!("段{段番号}のスカート{位置}番の複製元が表面に無い"),
    }
}

fn 外周にあるか(頂点: メッシュ頂点属性) -> bool {
    let 端 = 検査用一辺メートル;
    頂点.位置[0] == 0.0 || 頂点.位置[0] == 端 || 頂点.位置[2] == 0.0 || 頂点.位置[2] == 端
}
