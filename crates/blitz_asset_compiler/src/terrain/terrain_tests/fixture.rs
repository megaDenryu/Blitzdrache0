//! 検査が共通して使う地形の材料。高さの合成関数・格子の切り出し・焼いたシーンからの取り出しをここが所有する。
//! 辺分割数を16にするのは、段一覧が16・8・4の3段になり、段をまたぐ検査に隣り合う段の対が2つ現れるためである。

use crate::texture_storage::テクスチャ格納方針;
use std::path::PathBuf;

use blitz_engine::{シーンデータ, チャンク座標, メッシュデータ, メッシュ頂点属性, 描画形状};

use crate::generation_ledger::種の由来;
use crate::height_grid::{高さ格子, 高さ格子を切り出す, 高さ格子諸元};
use crate::placement::配置の種;
use crate::scene_compiler::ソースアセットのコンパイル係;
use crate::terrain::lod_level::地形段諸元;

pub(super) const 検査用辺分割数: u16 = 16;
pub(super) const 検査用一辺メートル: f32 = 100.0;

/// 大域サンプル添字だけから決まる高さ。隣接チャンクが共有する標本を同じ添字で参照するため、境界整合の前提を再現できる。
fn 検査用の高さ(添字x: i16, 添字z: i16) -> f32 {
    let x = f32::from(添字x);
    let z = f32::from(添字z);
    (x / 5.0).sin() * 3.0 + (z / 7.0).cos() * 2.0 + x * 0.05
}

/// 四隅が同一平面に乗らない鞍型の高さ。`検査用の高さ`はXだけの項とZだけの項の和であり、和へ分解できる高さでは
/// 升目の四隅が必ず同一平面に乗る。そこでは双一次の値と三角形の面が一致してしまうため、両者の差を見る検査には使えない。
/// XとZの積で作ると四隅の和が食い違い、升目の内部で双一次が面から外れる。
fn 鞍型の高さ(添字x: i16, 添字z: i16) -> f32 {
    (f32::from(添字x) / 5.0).sin() * (f32::from(添字z) / 7.0).cos() * 4.0
}

pub(super) fn 検査用諸元() -> 高さ格子諸元 {
    高さ格子諸元::生成する(検査用辺分割数, 1, 検査用一辺メートル).unwrap()
}

pub(super) fn 格子を切り出す(チャンク: チャンク座標) -> 高さ格子 {
    高さ格子を切り出す(検査用諸元(), チャンク, 検査用の高さ).unwrap()
}

pub(super) fn 鞍型格子を切り出す(チャンク: チャンク座標) -> 高さ格子 {
    高さ格子を切り出す(検査用諸元(), チャンク, 鞍型の高さ).unwrap()
}

pub(super) fn 段一覧() -> Vec<地形段諸元> {
    地形段諸元::段一覧を作る(検査用諸元())
}

/// 地形の構造だけを見る検査であるため、同居植生は指定しない。指定するとカタログから原型ソースを読む必要が生じ、
/// 高さ格子だけで閉じているこの検査へファイルの実在という別の前提が入る。
pub(super) fn シーンを焼く(チャンク: チャンク座標) -> シーンデータ {
    let カタログ = blitz_engine::カタログ::空を作る();
    ソースアセットのコンパイル係::生成する(
        &カタログ,
        テクスチャ格納方針::全てRGBA8,
        配置の種::種の由来から作る(種の由来::種を持たない),
    )
    .地形のシーンを組み立てる(&格子を切り出す(チャンク), チャンク, PathBuf::from("検査用"), None)
    .unwrap()
}

pub(super) fn 段別メッシュを取り出す(シーン: &シーンデータ) -> Vec<メッシュデータ> {
    match シーン.先頭の描画対象().形状() {
        描画形状::地形LODメッシュ群(群) => 群.段一覧().to_vec(),
        描画形状::通常メッシュ(_) | 描画形状::インスタンス群(_) => panic!("地形の描画対象が地形LODメッシュ群でない"),
    }
}

pub(super) fn 段の頂点一覧(チャンク: チャンク座標, 段番号: usize) -> Vec<メッシュ頂点属性> {
    段別メッシュを取り出す(&シーンを焼く(チャンク))[段番号].頂点一覧.clone()
}

/// 段の表面部分の頂点数。スカートの複製はこの後ろへ並ぶ。
pub(super) fn 表面頂点数(段諸元: 地形段諸元) -> usize {
    let 辺 = usize::try_from(段諸元.格子点数().unwrap()).unwrap();
    辺 * 辺
}
