//! 高さ格子の任意の局所座標での地表の面を求める工程。受け取るのは高さ格子とチャンク原点基準の局所メートル、
//! 返すのは升目の地表の面(高さと2方向の傾きと、どちらの三角形か)である。同居する植生や散布する個体を
//! どの高さへ置き、どう傾けるかがこの値で決まる。
//!
//! 升目の中の埋め方をこの工程は持たない。正本は`blitz_collision`の区分線形にあり、実行中の高さの問い合わせも
//! 同じ式を通る。焼くときと実行中で式を2つ持つと、置いた個体の足元と実行中の地面がいつか離れる。
//!
//! 四隅が同一平面にない鞍型の升目では双一次の値が三角形の面から外れるため、双一次で置いた個体は升目の内部で
//! 描画面に対して浮くか沈む。段が粗いフレームでは地形の面そのものが下がるため個体の足元が浮くが、
//! これは地形LODの本来の挙動であって配置の誤りではない。
//! 参照: `crates/blitz_asset_compiler/src/terrain/surface.rs`

use blitz_collision::height_field::{升目の一辺, 升目の中の比, 升目の四隅の高さ, 升目の地表の面};

use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子;
use crate::nonnegative_floor::負でない床をu16にする;

pub(crate) fn 地表高さを求める(格子: &高さ格子, 局所x: f32, 局所z: f32) -> Result<f32, アセットコンパイルエラー> {
    Ok(地表の面を求める(格子, 局所x, 局所z)?.高さ())
}

/// 升目の中を占める三角形の平面を、高さと2方向の傾きとして読む。傾きは升目の中の比に対する変化を刻みで割った値であり、
/// 1メートル進むときの高さの変化になる。四隅の高さの差が単精度の表せる範囲を越えて面が有限でなくなる格子は、
/// 衝突数学が型付きエラーで拒み、それがそのままアセットコンパイルエラーになる。
pub(crate) fn 地表の面を求める(
    格子: &高さ格子,
    局所x: f32,
    局所z: f32,
) -> Result<升目の地表の面<f32>, アセットコンパイルエラー> {
    let 刻み = 格子.諸元().刻みメートル();
    let (添字x, 比x) = 升目を求める(局所x / 刻み)?;
    let (添字z, 比z) = 升目を求める(局所z / 刻み)?;
    let 四隅 = 升目の四隅の高さ::生成する(
        格子.高さ(添字x, 添字z)?,
        格子.高さ(添字x + 1, 添字z)?,
        格子.高さ(添字x, 添字z + 1)?,
        格子.高さ(添字x + 1, 添字z + 1)?,
    )?;
    Ok(四隅.地表の面を求める(升目の中の比::生成する(比x, 比z)?, 升目の一辺::生成する(刻み)?)?)
}

/// 格子添字での実数位置から、それを含む升目の左下の格子添字と升目内の比を返す。
fn 升目を求める(実数位置: f32) -> Result<(i32, f32), アセットコンパイルエラー> {
    let 床 = 実数位置.floor();
    let 添字 = 負でない床をu16にする(床).ok_or(アセットコンパイルエラー::地表高さの座標範囲外(実数位置))?;
    Ok((i32::from(添字), 実数位置 - 床))
}
