//! 高さ格子の任意の局所座標での地表高さを求める工程。受け取るのは高さ格子とチャンク原点基準の局所メートル、
//! 返すのはその点の高さメートルである。同居する植生の個体をどの高さへ置くかがこの値で決まる。
//!
//! 升目の中は、最詳細段が実際に張る2つの三角形の平面をそのまま使う区分線形で求める。対角は`surface`が固定した
//! (添字x,添字z)から(添字x+1,添字z+1)への一本であり、点がどちらの三角形に属するかは升目内の比の大小で決まる。
//! 四隅が同一平面にない鞍型の升目では双一次の値が三角形の面から外れるため、双一次で置いた個体は升目の内部で
//! 描画面に対して浮くか沈む。段が粗いフレームでは地形の面そのものが下がるため個体の足元が浮くが、
//! これは地形LODの本来の挙動であって配置の誤りではない。
//! 参照: `crates/blitz_asset_compiler/src/terrain/surface.rs`

use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子;

pub(super) fn 地表高さを求める(格子: &高さ格子, 局所x: f32, 局所z: f32) -> Result<f32, アセットコンパイルエラー> {
    let 刻み = 格子.諸元().刻みメートル();
    let (添字x, 比x) = 升目を求める(局所x / 刻み)?;
    let (添字z, 比z) = 升目を求める(局所z / 刻み)?;
    let 手前左 = 格子.高さ(添字x, 添字z)?;
    let 奥右 = 格子.高さ(添字x + 1, 添字z + 1)?;
    if 比x <= 比z {
        let 奥左 = 格子.高さ(添字x, 添字z + 1)?;
        Ok(奥側の三角形の高さ(手前左, 奥左, 奥右, 比x, 比z))
    } else {
        let 手前右 = 格子.高さ(添字x + 1, 添字z)?;
        Ok(手前側の三角形の高さ(手前左, 手前右, 奥右, 比x, 比z))
    }
}

/// 対角より奥側にある三角形、すなわち手前左・奥左・奥右を頂点に持つ面の高さ。
/// 3頂点でそれぞれ手前左・奥左・奥右の値になり、比の1次式であるため面そのものを表す。
fn 奥側の三角形の高さ(手前左: f32, 奥左: f32, 奥右: f32, 比x: f32, 比z: f32) -> f32 {
    手前左 + (奥左 - 手前左) * 比z + (奥右 - 奥左) * 比x
}

/// 対角より手前側にある三角形、すなわち手前左・手前右・奥右を頂点に持つ面の高さ。
/// 対角の上では2つの式が同じ値を返すため、判定の等号をどちらへ寄せても面は途切れない。
fn 手前側の三角形の高さ(手前左: f32, 手前右: f32, 奥右: f32, 比x: f32, 比z: f32) -> f32 {
    手前左 + (手前右 - 手前左) * 比x + (奥右 - 手前右) * 比z
}

/// 格子添字での実数位置から、それを含む升目の左下の格子添字と升目内の比を返す。
fn 升目を求める(実数位置: f32) -> Result<(i32, f32), アセットコンパイルエラー> {
    let 床 = 実数位置.floor();
    let 添字 = 床をu16にする(床).ok_or(アセットコンパイルエラー::地表高さの座標範囲外(実数位置))?;
    Ok((i32::from(添字), 実数位置 - 床))
}

/// 非負のf32を切り捨ててu16にする。ワークスペースが数値のasキャストを禁じているため、ビットの重みを大きい側から引いて求める。
/// 参照: `crates/blitz_engine/src/streaming/chunk_grid.rs`の同型の変換
fn 床をu16にする(床: f32) -> Option<u16> {
    if !床.is_finite() || !(0.0..65_536.0).contains(&床) {
        return None;
    }
    let mut 残り = 床;
    let mut 整数 = 0_u16;
    for ビット in (0_u32..16).rev() {
        let 重み = 1_u16 << ビット;
        if 残り >= f32::from(重み) {
            整数 |= 重み;
            残り -= f32::from(重み);
        }
    }
    Some(整数)
}
