//! 縁の一致の検査で破れうる前提の型付きエラー。隣り合う格子が同じ諸元を持つことと、重なり帯の全ての格子点で
//! 同じ高さを持つことの2つがここで破れる。

use thiserror::Error;

use crate::height_grid::高さ格子エラー;

#[derive(Debug, Error)]
pub enum 縁の一致エラー {
    #[error("チャンク(東{東}、南{南})の高さ格子の諸元が他のチャンクと食い違う")]
    諸元がチャンク間で食い違う { 東: i32, 南: i32 },
    #[error(
        "チャンク(東{東}、南{南})とチャンク(東{隣の東}、南{隣の南})が重なる帯の格子点(帯を横切る位置{帯を横切る位置}、帯に沿う位置{帯に沿う位置})で高さが食い違う({高さ}メートルと{隣の高さ}メートル)"
    )]
    重なり帯の高さが隣り合うチャンクで食い違う {
        東: i32,
        南: i32,
        隣の東: i32,
        隣の南: i32,
        帯を横切る位置: i32,
        帯に沿う位置: i32,
        高さ: f32,
        隣の高さ: f32,
    },
    #[error("高さ格子の読み出しに失敗した: {0}")]
    高さ格子の読み出しに失敗した(#[from] 高さ格子エラー),
}
