//! 縁の一致の反証。同じ大域サンプル格子から切り出した隣り合う格子が通ること、共有する1列は揃っているのに
//! その外側の重なり帯だけが食い違う格子を拒むこと、諸元の食い違いを拒むこと、隣が居ない世界の端を
//! 欠けとして拒まないことを確かめる。

#![allow(clippy::unwrap_used)]

use blitz_engine::チャンク座標;

use super::error::縁の一致エラー;
use super::pairwise::隣り合うチャンクの重なり帯が一致することを確かめる;
use crate::height_grid::{高さ格子, 高さ格子を切り出す, 高さ格子諸元};

const 辺分割数: u16 = 4;
const 重なり幅: u8 = 1;

fn 諸元() -> 高さ格子諸元 {
    高さ格子諸元::生成する(辺分割数, 重なり幅, 100.0).unwrap()
}

fn 大域の高さ(東: i16, 南: i16) -> f32 {
    f32::from(東) + f32::from(南) * 10.0
}

fn 東西に並ぶ二つの格子() -> Vec<(チャンク座標, 高さ格子)> {
    [チャンク座標::生成する(0, 0), チャンク座標::生成する(1, 0)]
        .into_iter()
        .map(|座標| (座標, 高さ格子を切り出す(諸元(), 座標, 大域の高さ).unwrap()))
        .collect()
}

#[test]
fn 同じ大域格子から切り出した隣り合う格子は一致する() {
    assert!(隣り合うチャンクの重なり帯が一致することを確かめる(&東西に並ぶ二つの格子()).is_ok());
}

#[test]
fn 隣が居ない世界の端を欠けとして拒まない() {
    let 一つだけ = vec![(
        チャンク座標::生成する(5, 7),
        高さ格子を切り出す(諸元(), チャンク座標::生成する(5, 7), 大域の高さ).unwrap(),
    )];
    assert!(隣り合うチャンクの重なり帯が一致することを確かめる(&一つだけ).is_ok());
}

/// 隣の格子の重なり帯(格子添字-1の列)だけを書き換える。共有する1列(手前の上限と隣の0)は揃ったままであるため、
/// 共有する列だけを見る検査では通ってしまう食い違いである。
#[test]
fn 共有する列は揃っていても重なり帯が食い違えば拒む() {
    let mut 一覧 = 東西に並ぶ二つの格子();
    一覧[1].1 = 重なり帯の一点を書き換えた格子を作る(&一覧[1].1, -1, 0);
    let 結果 = 隣り合うチャンクの重なり帯が一致することを確かめる(&一覧);
    assert!(matches!(
        結果,
        Err(縁の一致エラー::重なり帯の高さが隣り合うチャンクで食い違う {
            東: 0,
            南: 0,
            隣の東: 1,
            隣の南: 0,
            帯を横切る位置: -1,
            帯に沿う位置: 0,
            ..
        })
    ));
}

fn 重なり帯の一点を書き換えた格子を作る(元の格子: &高さ格子, 格子添字x: i32, 格子添字z: i32) -> 高さ格子 {
    let 諸元 = 元の格子.諸元();
    let 重なり = i32::from(諸元.重なり幅());
    let 辺 = i32::try_from(諸元.保存辺長()).unwrap();
    let 位置 = usize::try_from((格子添字z + 重なり) * 辺 + (格子添字x + 重なり)).unwrap();
    let mut 高さ一覧 = 元の格子.高さ一覧().to_vec();
    高さ一覧[位置] += 1.0;
    高さ格子::生成する(諸元, 高さ一覧).unwrap()
}

#[test]
fn 諸元の食い違う格子を拒む() {
    let mut 一覧 = 東西に並ぶ二つの格子();
    let 別の諸元 = 高さ格子諸元::生成する(8, 重なり幅, 100.0).unwrap();
    一覧[1].1 = 高さ格子を切り出す(別の諸元, 一覧[1].0, 大域の高さ).unwrap();
    let 結果 = 隣り合うチャンクの重なり帯が一致することを確かめる(&一覧);
    assert!(matches!(結果, Err(縁の一致エラー::諸元がチャンク間で食い違う { 東: 1, 南: 0 })));
}
