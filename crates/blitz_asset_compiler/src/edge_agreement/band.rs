//! 隣り合う2つの高さ格子が重なる帯を、格子点1つずつ突き合わせる工程。受け取るのは手前と隣の格子と隣り合う向き、
//! 返すのは突き合わせの成否である。
//!
//! 共有する1列だけでなく重なり帯の全体を見るのは、帯が法線の計算に使われるためである。帯の中で値が食い違うと、
//! 境界の格子点の高さが揃っていても法線が両側で食い違い、隣り合うチャンクの継ぎ目に陰影の段差が出る。
//! 帯の値は元の大域サンプル格子から引かれるため、チャンクを別々に焼き直せる状態では値で確かめるほかに拠り所が無い。

use blitz_engine::チャンク座標;

use super::error::縁の一致エラー;
use crate::height_grid::高さ格子;

/// 隣り合う2つのチャンクのどちらの向きで隣り合っているか。帯の格子添字の作り方がこの2枝で変わる。
#[derive(Clone, Copy)]
pub(super) enum 隣り合う向き {
    東,
    南,
}

impl 隣り合う向き {
    pub(super) fn 隣の座標を求める(self, 手前の座標: チャンク座標) -> チャンク座標 {
        match self {
            Self::東 => チャンク座標::生成する(手前の座標.x() + 1, 手前の座標.z()),
            Self::南 => チャンク座標::生成する(手前の座標.x(), 手前の座標.z() + 1),
        }
    }
}

pub(super) fn 一組の重なり帯を突き合わせる(
    手前の座標: チャンク座標,
    手前の格子: &高さ格子,
    隣の格子: &高さ格子,
    向き: 隣り合う向き,
) -> Result<(), 縁の一致エラー> {
    let 諸元 = 手前の格子.諸元();
    let 重なり幅 = i32::from(諸元.重なり幅());
    let 辺分割数 = i32::from(諸元.辺分割数());
    for 帯を横切る位置 in -重なり幅..=重なり幅 {
        for 帯に沿う位置 in -重なり幅..=(辺分割数 + 重なり幅) {
            let (手前x, 手前z, 隣x, 隣z) = 格子添字を組み立てる(向き, 辺分割数, 帯を横切る位置, 帯に沿う位置);
            let 高さ = 手前の格子.高さ(手前x, 手前z)?;
            let 隣の高さ = 隣の格子.高さ(隣x, 隣z)?;
            // 同じ大域サンプル添字から引いた標本はビットまで同じになるため、値でなくビット列で比べる。
            // 浮動小数の等価比較では非数どうしが常に食い違いになり、正のゼロと負のゼロが同じ値として通ってしまう。
            if 高さ.to_bits() == 隣の高さ.to_bits() {
                continue;
            }
            return Err(食い違いを組み立てる(
                手前の座標,
                向き,
                (帯を横切る位置, 帯に沿う位置),
                (高さ, 隣の高さ),
            ));
        }
    }
    Ok(())
}

/// 手前の格子の帯は自分の上限の側にあり、隣の格子の同じ点は0の側にある。帯を横切る位置はその2つの基準からの差である。
fn 格子添字を組み立てる(
    向き: 隣り合う向き, 辺分割数: i32, 帯を横切る位置: i32, 帯に沿う位置: i32
) -> (i32, i32, i32, i32) {
    match 向き {
        隣り合う向き::東 => (辺分割数 + 帯を横切る位置, 帯に沿う位置, 帯を横切る位置, 帯に沿う位置),
        隣り合う向き::南 => (帯に沿う位置, 辺分割数 + 帯を横切る位置, 帯に沿う位置, 帯を横切る位置),
    }
}

fn 食い違いを組み立てる(
    手前の座標: チャンク座標,
    向き: 隣り合う向き,
    帯の位置: (i32, i32),
    食い違った高さ: (f32, f32),
) -> 縁の一致エラー {
    let 隣の座標 = 向き.隣の座標を求める(手前の座標);
    縁の一致エラー::重なり帯の高さが隣り合うチャンクで食い違う {
        東: 手前の座標.x(),
        南: 手前の座標.z(),
        隣の東: 隣の座標.x(),
        隣の南: 隣の座標.z(),
        帯を横切る位置: 帯の位置.0,
        帯に沿う位置: 帯の位置.1,
        高さ: 食い違った高さ.0,
        隣の高さ: 食い違った高さ.1,
    }
}
