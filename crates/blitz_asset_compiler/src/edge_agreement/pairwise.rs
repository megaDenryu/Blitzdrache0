//! チャンクの集まり全体を、東どうしと南どうしの隣り合わせで走査する工程。受け取るのはチャンク座標と高さ格子の組の一覧、
//! 返すのは検査の成否である。
//!
//! 隣が一覧に無い座標を欠けとして拒まないのは、この検査が世界の端でも成り立つ必要があるためである。
//! 矩形をなすことを要求するのは高さ場へ貼り合わせる側の都合であり、縁の一致そのものの前提ではない。
//!
//! 角で斜めに隣り合う2つのチャンクを別に調べないのは、東どうしと南どうしの突き合わせが帯の全体を覆い、
//! 角の格子点が東と南の連鎖で1つの値へ結ばれるためである。
//!
//! 諸元が揃っていることを先に確かめるのは、格子添字の範囲が諸元から決まるためである。細かさの違う格子どうしを
//! 添字で突き合わせても、同じ大域の点を比べたことにならない。

use std::collections::HashMap;

use blitz_engine::チャンク座標;

use super::band::{一組の重なり帯を突き合わせる, 隣り合う向き};
use super::error::縁の一致エラー;
use crate::height_grid::{高さ格子, 高さ格子諸元};

pub fn 隣り合うチャンクの重なり帯が一致することを確かめる(
    格子一覧: &[(チャンク座標, 高さ格子)],
) -> Result<(), 縁の一致エラー> {
    let Some((_, 先頭の格子)) = 格子一覧.first() else {
        return Ok(());
    };
    諸元が揃っていることを確かめる(格子一覧, 先頭の格子.諸元())?;
    let 索引: HashMap<(i32, i32), &高さ格子> = 格子一覧.iter().map(|(チャンク, 格子)| ((チャンク.x(), チャンク.z()), 格子)).collect();
    for (座標, 格子) in 格子一覧 {
        隣が在る向きだけ突き合わせる(*座標, 格子, &索引)?;
    }
    Ok(())
}

fn 隣が在る向きだけ突き合わせる(
    座標: チャンク座標,
    格子: &高さ格子,
    索引: &HashMap<(i32, i32), &高さ格子>,
) -> Result<(), 縁の一致エラー> {
    for 向き in [隣り合う向き::東, 隣り合う向き::南] {
        let 隣の座標 = 向き.隣の座標を求める(座標);
        let Some(隣の格子) = 索引.get(&(隣の座標.x(), 隣の座標.z())) else {
            continue;
        };
        一組の重なり帯を突き合わせる(座標, 格子, 隣の格子, 向き)?;
    }
    Ok(())
}

fn 諸元が揃っていることを確かめる(
    格子一覧: &[(チャンク座標, 高さ格子)],
    基準の諸元: 高さ格子諸元,
) -> Result<(), 縁の一致エラー> {
    for (チャンク, 格子) in 格子一覧 {
        if 格子.諸元() != 基準の諸元 {
            return Err(縁の一致エラー::諸元がチャンク間で食い違う {
                東: チャンク.x(),
                南: チャンク.z(),
            });
        }
    }
    Ok(())
}
