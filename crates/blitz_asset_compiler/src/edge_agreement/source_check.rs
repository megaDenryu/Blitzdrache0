//! ソースの一覧から高さ格子を読み、重なり帯の一致を確かめる局面。受け取るのはチャンクの高さ格子ソースの一覧、
//! 返すのは検査の成否である。呼ばれるのは1つの世界のコンパイルにつき1回である。
//!
//! 高さ場を焼かない世界にもこの入口が要るのは、地形メッシュを焼く経路がチャンクを1つずつ独立に焼くためである。
//! チャンクを別々に焼き直せるようになると、縁が食い違ったまま片方だけ新しくなる状態が起こりうる。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

use rayon::iter::{IntoParallelRefIterator, ParallelIterator};

use super::error::縁の一致エラー;
use super::pairwise::隣り合うチャンクの重なり帯が一致することを確かめる;
use crate::asset_layout::{チャンクの高さ格子, チャンクの高さ格子ソース};

pub fn ソースの高さ格子の重なり帯が一致することを確かめる(
    チャンクごとのソース一覧: &[チャンクの高さ格子ソース],
) -> Result<(), 縁の一致エラー> {
    let 格子一覧 = チャンクごとのソース一覧
        .par_iter()
        .map(チャンクの高さ格子ソース::読み込む)
        .collect::<Result<Vec<チャンクの高さ格子>, _>>()?;
    隣り合うチャンクの重なり帯が一致することを確かめる(&格子一覧)
}
