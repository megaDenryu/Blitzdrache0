//! 復号済みの高さ格子一覧に対する、目録の一辺との一致検査を固定する。

#![allow(clippy::unwrap_used)]

use blitz_engine::{チャンク一辺, チャンク座標};

use super::error::縁の一致エラー;
use super::source_check::目録と高さ格子の一辺が一致することを確かめる;
use crate::asset_layout::チャンクの高さ格子;
use crate::height_grid::{高さ格子, 高さ格子諸元};

fn 高さ格子を作る(一辺メートル: f32) -> チャンクの高さ格子 {
    let 諸元 = 高さ格子諸元::生成する(2, 1, 一辺メートル).unwrap();
    let 格子点数 = usize::try_from(諸元.保存辺長()).unwrap().pow(2);
    チャンクの高さ格子::生成する(チャンク座標::生成する(3, -2), 高さ格子::生成する(諸元, vec![0.0; 格子点数]).unwrap())
}

#[test]
fn 目録と高さ格子の一辺が一致すれば通る() {
    let 一辺 = チャンク一辺::生成する(256.0).unwrap();
    assert!(目録と高さ格子の一辺が一致することを確かめる(一辺, &[高さ格子を作る(256.0)]).is_ok());
}

#[test]
fn 目録と高さ格子の一辺が違えば座標つきで拒む() {
    let 一辺 = チャンク一辺::生成する(256.0).unwrap();
    let 結果 = 目録と高さ格子の一辺が一致することを確かめる(一辺, &[高さ格子を作る(100.0)]);
    assert!(matches!(
        結果,
        Err(縁の一致エラー::チャンク一辺不一致 {
            目録: 256.0,
            高さ格子: 100.0,
            x: 3,
            z: -2
        })
    ));
}
