//! glTF読込と画像デコードの型付きエラー。

use blitz_engine::アセットID;
use thiserror::Error;

#[derive(Debug, Error)]
pub enum アセットコンパイルエラー {
    #[error("カタログに未登録のアセットID: {0}")]
    カタログ未登録(アセットID),
    #[error("ファイル読込に失敗した: {0}")]
    ファイル読込失敗(String),
    #[error("glTFの解析に失敗した: {0}")]
    解析失敗(String),
    #[error("画像デコードに失敗した: {0}")]
    画像デコード失敗(String),
    #[error("glTFにメッシュが無い")]
    メッシュなし,
    #[error("メッシュにプリミティブが無い")]
    プリミティブなし,
    #[error("プリミティブに頂点位置(POSITION)が無い")]
    頂点位置なし,
    #[error("未対応のバッファ形式(data URI等)")]
    未対応バッファ形式,
    #[error("未対応の画像形式(data URI等)")]
    未対応画像形式,
    #[error("スキン付きプリミティブにJOINTS_0またはWEIGHTS_0が無い")]
    スキン頂点属性なし,
    #[error("CUBICSPLINE補間は未対応(判断42のスコープ外)")]
    補間CUBICSPLINE未対応,
    #[error("アセット実行時形式への変換に失敗した: {0}")]
    実行時形式変換失敗(#[from] blitz_engine::アセット実行時形式エラー),
    #[error("チャンク目録ソースの形式宣言が不正である: {0}")]
    チャンク目録ソース形式不正(String),
    #[error("未対応のチャンク目録ソース版だった: {0}")]
    チャンク目録ソース未対応版(String),
    #[error("チャンク目録ソースの{行番号}行目が不正である: {内容}")]
    チャンク目録ソース行不正 { 行番号: usize, 内容: String },
    #[error("高さ格子の扱いに失敗した: {0}")]
    高さ格子失敗(#[from] crate::height_grid::高さ格子エラー),
    #[error("地形の詳細段の組み立てに失敗した: {0}")]
    地形LODメッシュ群失敗(#[from] blitz_engine::地形LODメッシュ群エラー),
    #[error("インスタンス群の組み立てに失敗した: {0}")]
    インスタンス群失敗(#[from] blitz_engine::インスタンス群エラー),
    #[error("材質集合の組み立てに失敗した: {0}")]
    材質集合失敗(#[from] blitz_engine::材質集合エラー),
    /// 語彙はプリミティブの走査から作るため、走査に含めたメッシュのプリミティブは必ず引ける。
    #[error("プリミティブのマテリアルが材質スロットの語彙に無い")]
    材質スロット未登録,
    #[error("寸法を合わせる一様倍率が正の有限値でない: {0}")]
    寸法の一様倍率が正の有限値でない(f32),
    #[error("植生の個体数が受け取れる範囲にない: {0}")]
    植生個体数不正(usize),
    #[error("植生の原型が広がりを持たない")]
    植生原型の広がりなし,
    /// 原型は全段で1つのマテリアルを共有する。段ごとの違いを無言で捨てて先頭段のマテリアルを全段へ適用しない。
    #[error("原型の段{段番号}のマテリアルが先頭段と一致しない")]
    原型の段間マテリアル不一致 { 段番号: usize },
    #[error("原型の段{段番号}のUV座標(TEXCOORD_0)の有無が先頭段と一致しない")]
    原型の段間UV有無不一致 { 段番号: usize },
    #[error("個体別LODの検収配置で狙った距離{0}が視点との高さ差と横のずれに足りない")]
    植生詳細段弧の距離不足(f32),
    #[error("地表高さを参照する格子添字{0}が扱える範囲にない")]
    地表高さの座標範囲外(f32),
    /// 集落は小物の群を見るための世界であるため、群が1つも無い宣言は宣言の書き誤りである。
    #[error("見本の集落へ散らす小物の群が1つも宣言されていない")]
    見本の集落に群が無い,
    #[error("散布の走査の列数が受け取れる範囲にない: {0}")]
    散布の走査の列数不正(u8),
    #[error("散布の密度場の升目の標本数が正でない: {0}")]
    散布の密度場の升目が正でない(i16),
    #[error("散布の出現の割合が0以上1以下で下限が上限以下でない: 下限{下限} 上限{上限}")]
    散布の出現割合不正 { 下限: f32, 上限: f32 },
    #[error("散布の大きさの範囲が正で下限が上限以下でない: 下限{下限} 上限{上限}")]
    散布の大きさの範囲不正 { 下限: f32, 上限: f32 },
    #[error("散布の傾きの閾値が有限な非負の値でない: {0}")]
    散布の傾きの閾値不正(f32),
    #[error("散布の大域サンプル添字がi16の範囲を超えた: チャンク成分{チャンク成分}")]
    散布の大域サンプル添字が範囲外 { チャンク成分: i32 },
    #[error("テクスチャの格納バイト数の算術に失敗した: {0}")]
    テクスチャ格納バイト数の算術失敗(#[from] blitz_engine::texture_storage::テクスチャ格納バイト数エラー),
    #[error("縮小段の画素列の長さが寸法と食い違う: 幅{幅} 高さ{高さ} 長さ{長さ}")]
    縮小段の画素列の長さが寸法と食い違う { 幅: u32, 高さ: u32, 長さ: usize },
    #[error("テクスチャの寸法が添字の型に収まらない: {0}")]
    テクスチャの寸法が添字の型に収まらない(u32),
    #[error("テクスチャの格納バイト数が添字の型に収まらない: {0}")]
    テクスチャの格納バイト数が添字の型に収まらない(u64),
    #[error("テクスチャの縮小段の並びが条件を満たさない: {0}")]
    格納済みテクスチャ不正(#[from] blitz_engine::texture_storage::格納済みテクスチャエラー),
    /// BC1は色の3成分だけを運ぶため、半透明を無言で不透明へ倒さずに焼くことを拒む。
    #[error("ブロック圧縮で焼くベースカラーの画素{画素番号}の不透明度が{不透明度}であり255でない")]
    ブロック圧縮のベースカラーに不透明でない画素がある { 画素番号: usize, 不透明度: u8 },
}
