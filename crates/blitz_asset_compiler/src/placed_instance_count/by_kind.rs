//! 種類ごとの置いた個体の数。担当するのは、散らした種類の名前と、その種類が置いた個体の数の対を積み上げることである。
//!
//! **合計だけでは木と岩の取り分が分からない。** 世界全体の個体数は焼く工程が既に報告しているが、その数は
//! 岩2種と木を合わせた値であり、木を1本増やすと何体増えるのかを外から読めない。1個体が複数の部品になる散布を
//! 入れる以上、種類ごとの内訳が無いと物量の議論ができない。
//!
//! 名前を裸の文字列で持たないのは、安定IDの綴りと種類の名前と部品IDがどれも文字列であり、
//! 引数として並べると取り違えても型が通るためである。

use std::collections::BTreeMap;

use super::置いた個体の数;
use crate::error::アセットコンパイルエラー;

/// 散らした種類1つの名前。原型を散らすなら原型の安定ID、部品で組む散布なら部品の安定IDである。
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct 散らした種類の名前(String);

impl 散らした種類の名前 {
    pub fn 綴りから生成する(綴り: &str) -> Self {
        Self(綴り.to_string())
    }

    pub fn 綴り(&self) -> &str {
        &self.0
    }
}

/// 種類ごとの置いた個体の数。名前の順に畳むのは、同じ入力から同じ綴りの報告を得るためである。
#[derive(Debug, Clone, Default)]
pub struct 種類ごとの置いた個体の数 {
    一覧: BTreeMap<散らした種類の名前, 置いた個体の数>,
}

impl 種類ごとの置いた個体の数 {
    pub fn 空から始める() -> Self {
        Self { 一覧: BTreeMap::new() }
    }

    pub fn 一種類ぶんを積む(
        &mut self, 名前: 散らした種類の名前, 数: 置いた個体の数
    ) -> Result<(), アセットコンパイルエラー> {
        let 既存 = self.一覧.get(&名前).copied().unwrap_or_else(置いた個体の数::零);
        self.一覧.insert(名前, 既存.足す(数)?);
        Ok(())
    }

    /// 別の内訳を取り込む。チャンクごとの内訳を世界の内訳へ畳むときに使う。
    pub fn 内訳を取り込む(&mut self, 他: &Self) -> Result<(), アセットコンパイルエラー> {
        for (名前, 数) in &他.一覧 {
            self.一種類ぶんを積む(名前.clone(), *数)?;
        }
        Ok(())
    }

    /// 名前の順に並べた対の一覧。報告の行を組み立てる側がこれを綴る。
    pub fn 名前の順に並べる(&self) -> Vec<(&散らした種類の名前, 置いた個体の数)> {
        self.一覧.iter().map(|(名前, 数)| (名前, *数)).collect()
    }
}
