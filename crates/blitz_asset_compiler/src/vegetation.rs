//! glTFの原型と決定的な配置生成から、インスタンス群を1つ持つチャンクの実行時シーンを焼く。
//! 走査順・混合関数の種・格子の刻みをすべて固定しているため、同じ原型と同じ個体数からは常に同じバイト列を得る。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「インスタンス群の表現」

mod bounds;
mod deterministic_value;
mod placement;
#[cfg(test)]
mod vegetation_tests;

use blitz_engine::{
    アセットID, インスタンス群, カタログ, シーンを実行時形式へ格納する, シーンデータ, チャンク座標, 原型, 描画対象ID, 描画対象データ, 描画形状,
};

use crate::compile::{コンパイル済みシーン, メタデータを集計する};
use crate::error::アセットコンパイルエラー;
use crate::loader::ソースシーンを読み込む;

/// 植生チャンクの描画対象番号。1つのチャンクが1つの群になるため常にこの値である。
const 植生描画対象番号: u64 = 0;

pub fn 植生チャンクをコンパイルする(
    カタログ: &カタログ,
    id: &アセットID,
    所有チャンク: チャンク座標,
    個体数: usize,
) -> Result<コンパイル済みシーン, アセットコンパイルエラー> {
    let シーン = シーンを組み立てる(カタログ, id, 所有チャンク, 個体数)?;
    let メタデータ = メタデータを集計する(&シーン)?;
    let 実行時バイト列 = シーンを実行時形式へ格納する(&シーン)?;
    Ok(コンパイル済みシーン {
        実行時バイト列,
        ソース依存一覧: シーン.参照ファイル一覧,
        メタデータ,
    })
}

/// 原型のメッシュとマテリアルはソースglTFの先頭の描画対象から取る。群の全個体が共有するマテリアルは
/// 外側の描画対象データが持つため、原型はメッシュ列だけを持つ。
fn シーンを組み立てる(
    カタログ: &カタログ,
    id: &アセットID,
    所有チャンク: チャンク座標,
    個体数: usize,
) -> Result<シーンデータ, アセットコンパイルエラー> {
    let ソース = ソースシーンを読み込む(カタログ, id, 所有チャンク)?;
    let 元対象 = ソース.先頭の描画対象();
    let 段一覧 = vec![元対象.形状().最詳細メッシュ().clone()];
    let 配置一覧 = placement::配置列を作る(個体数)?;
    let 境界 = bounds::境界を求める(&段一覧, &配置一覧)?;
    let 群 = インスタンス群::生成する(原型::生成する(段一覧)?, 配置一覧, 境界)?;
    let 対象 = 描画対象データ::生成する(
        描画対象ID::生成する(植生描画対象番号),
        所有チャンク,
        元対象.ローカルからワールド(),
        描画形状::インスタンス群(群),
        元対象.マテリアル().clone(),
    );
    Ok(シーンデータ::生成する(
        対象,
        Vec::new(),
        ソース.参照ファイル一覧.clone(),
        None,
        Vec::new(),
    ))
}
