//! 高さ格子と小物の原型から、見本の集落1チャンク分の実行時シーンを焼く。
//!
//! 地形の世界の同居植生と違うのは2つである。1つは群を種の数だけ持つことであり、もう1つは群の共有マテリアルを
//! 原型のglTFが宣言したものにすることである。小物は種ごとに色が違い、その色は生成した本人がベースカラー係数で
//! 与えているためである。
//!
//! 地形の焼き方と群の組み立て方と混合関数は地形・植生の工程をそのまま呼ぶ。写しを持つと、同じ地面から
//! 別の三角形が出たり、同じ宣言から別の配置が出たりして、どちらが正かが決まらなくなる。
//! 参照: `_doc/設計/Blenderアセット運用.md`「段3: 小物の量産と見本の集落」

mod layout;
mod placement;
mod scene;

pub use placement::配置様式;

use blitz_engine::{アセットID, カタログ, シーンを実行時形式へ格納する, チャンク座標};

use crate::compile::{コンパイル済みシーン, メタデータを集計する};
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子を読み込む;

/// 集落へ散らす小物1種の指定。原型と個体数と並べ方の3つで1種が決まる。
pub struct 小物群の指定 {
    pub 原型id: アセットID,
    pub 個体数: usize,
    pub 配置様式: 配置様式,
}

pub fn 見本の集落チャンクをコンパイルする(
    カタログ: &カタログ,
    id: &アセットID,
    所有チャンク: チャンク座標,
    群一覧: &[小物群の指定],
) -> Result<コンパイル済みシーン, アセットコンパイルエラー> {
    let パス = カタログ
        .パスを参照する(id)
        .ok_or_else(|| アセットコンパイルエラー::カタログ未登録(id.clone()))?;
    let 格子 = 高さ格子を読み込む(パス)?;
    let シーン = scene::組み立てる(カタログ, &格子, 所有チャンク, パス.to_path_buf(), 群一覧)?;
    let メタデータ = メタデータを集計する(&シーン)?;
    let 実行時バイト列 = シーンを実行時形式へ格納する(&シーン)?;
    Ok(コンパイル済みシーン {
        実行時バイト列,
        ソース依存一覧: シーン.参照ファイル一覧,
        メタデータ,
    })
}
