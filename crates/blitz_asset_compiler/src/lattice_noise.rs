//! 種と格子の升目から-1以上1以下の値を作る格子雑音の工程。受け取るのは種と大域サンプル添字と1つの升目の幅、
//! 返すのはその位置の値である。整数の演算と滑らかな内挿だけで作るため、同じ種と同じ添字からは常に同じビット列が出る。
//!
//! 三角関数を使わないのは、超越関数の近似が処理系ごとに違い、別の機材で焼き直した高さの末尾ビットが変わるためである。
//! 位置を実数のメートルでなく大域サンプル添字のまま扱うのは、升目の境目を整数の除算と剰余で求めるためであり、
//! 実数から整数への切り捨てを1度も通さずに済む。
//!
//! 生成器の高さの層とコンパイラの散布の密度場がどちらもこの1つを読む。写しを持つと、高さが作る地形と
//! 密度が指す地形が別物になり、山の斜面を避けたはずの木が斜面に立つ。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「判断j」

/// 32ビットの値をよく混ぜる整数ハッシュ。同じ入力からは常に同じ出力が出る。0は0へ写るため、
/// 「種を持たない世界では恒等」という不変条件を持つ`配置の種`もこれを共有できる。
/// 写しを作らずここを共有するのは、混合の定数が2箇所に分かれると片方だけが直る事故を招くためである。
pub(crate) fn 整数を混ぜる(値: u32) -> u32 {
    let mut 混ぜた = 値;
    混ぜた ^= 混ぜた >> 16;
    混ぜた = 混ぜた.wrapping_mul(0x7feb_352d);
    混ぜた ^= 混ぜた >> 15;
    混ぜた = 混ぜた.wrapping_mul(0x846c_a68b);
    混ぜた ^= 混ぜた >> 16;
    混ぜた
}

/// 符号付き整数を、値を落とさずに同じ幅の符号なし整数のビット列として読む。数値のasキャストを使わないための写しである。
fn 符号付き整数のビット列(値: i32) -> u32 {
    u32::from_ne_bytes(値.to_ne_bytes())
}

/// 升目の1つの隅に割り当てる-1以上1以下の値。
fn 升目の隅の値(種: u32, 升目x: i32, 升目z: i32) -> f32 {
    let 混ぜた = 整数を混ぜる(符号付き整数のビット列(升目x) ^ 整数を混ぜる(符号付き整数のビット列(升目z).wrapping_add(種)));
    let バイト列 = 混ぜた.to_le_bytes();
    let 上位 = u16::from_le_bytes([バイト列[2], バイト列[3]]);
    f32::from(上位) / 32_767.5 - 1.0
}

/// 升目の中の比を、両端で傾きが0になる三次曲線へ写す。升目の隅の値をそのまま線形につなぐと升目の境目に折れ目が残る。
fn なめらかな比へ写す(比: f32) -> f32 {
    比 * 比 * (3.0 - 2.0 * 比)
}

/// 1つの軸について、大域サンプル添字が載る升目の番号と升目の中の比を求める。
fn 升目の番号と比を求める(添字: i16, 升目の幅: i16) -> (i32, f32) {
    let 番号 = 添字.div_euclid(升目の幅);
    let 余り = 添字.rem_euclid(升目の幅);
    (i32::from(番号), f32::from(余り) / f32::from(升目の幅))
}

/// 指定の升目の幅で作った格子雑音の値。値域は-1以上1以下である。
pub fn 格子雑音の値(種: u32, 添字x: i16, 添字z: i16, 升目の幅: i16) -> f32 {
    let (升目x, 比x) = 升目の番号と比を求める(添字x, 升目の幅);
    let (升目z, 比z) = 升目の番号と比を求める(添字z, 升目の幅);
    let 重みx = なめらかな比へ写す(比x);
    let 重みz = なめらかな比へ写す(比z);
    let 手前 = 一次内挿した値(升目の隅の値(種, 升目x, 升目z), 升目の隅の値(種, 升目x + 1, 升目z), 重みx);
    let 奥 = 一次内挿した値(升目の隅の値(種, 升目x, 升目z + 1), 升目の隅の値(種, 升目x + 1, 升目z + 1), 重みx);
    一次内挿した値(手前, 奥, 重みz)
}

fn 一次内挿した値(始め: f32, 終わり: f32, 重み: f32) -> f32 {
    始め + (終わり - 始め) * 重み
}
