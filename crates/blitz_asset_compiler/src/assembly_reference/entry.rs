//! 正解表とその1件。部品IDと、建物の原点を基準にしたワールド姿勢の組である。
//!
//! 姿勢を`個体配置`でなく生の成分で持つのは、この表が外から来たデータであり、こちらの不変条件(チャンクの基準原点
//! からの距離の上限など)を満たすとは限らないためである。突き合わせる側が自分の判断で型へ写す。

/// 正解表の1件。平行移動と回転と倍率はglTFの座標系で書かれている。
#[derive(Debug, Clone, PartialEq)]
pub struct 正解の姿勢 {
    pub 部品の識別子: String,
    pub 平行移動: [f32; 3],
    pub 回転: [f32; 4],
    pub 倍率: [f32; 3],
}

#[derive(Debug, Clone, PartialEq)]
pub struct 正解表 {
    組み立ての識別子: String,
    姿勢一覧: Vec<正解の姿勢>,
}

impl 正解表 {
    pub(super) fn 組み立てと姿勢から生成する(組み立ての識別子: String, 姿勢一覧: Vec<正解の姿勢>) -> Self {
        Self {
            組み立ての識別子, 姿勢一覧
        }
    }

    /// この表がどの組み立てのものか。突き合わせる側はこの値で手順を選ぶ。
    pub fn 組み立ての識別子(&self) -> &str {
        &self.組み立ての識別子
    }

    pub fn 姿勢一覧(&self) -> &[正解の姿勢] {
        &self.姿勢一覧
    }

    /// 部品の識別子で正解の姿勢を全件引く。**同じ部品が何度も現れる表がある。** 木は幹を3節・枝を3本・
    /// 葉房を4つ持つため、最初の1件だけを返すと正しい組み立てが食い違いとして出る。
    /// 並びは表に書かれた順であり、どの行をどの配置へ当てるかは突き合わせる側が決める。
    pub fn 部品で全件引く(&self, 部品の識別子: &str) -> Vec<&正解の姿勢> {
        self.姿勢一覧.iter().filter(|姿勢| 姿勢.部品の識別子 == 部品の識別子).collect()
    }
}
