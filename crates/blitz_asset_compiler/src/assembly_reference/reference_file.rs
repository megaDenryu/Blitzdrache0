//! 組み立ての正解表のファイル: 正解表を指す役割つきのパス。担当するのは、そのファイルを開いて正解表を作ることである。
//!
//! 裸のパスでなく役割の型で受けるのは、この口が受け取れるのが正解表のJSONだけであり、
//! 部品のglbや出力先のパスを渡しても裸の`&Path`では型が通るためである。
//!
//! 座標系の綴りを確かめるのは、Blender側が座標系を変えた表を渡してきたときに黙って読むと、
//! 突き合わせの不一致が「接合の計算が誤っている」という別の結論に化けるためである。

use std::path::{Path, PathBuf};

use serde_json::Value;

use super::entry::{正解の姿勢, 正解表};
use super::error::正解表の読み込みエラー;
use super::value_read::{三成分を読む, 四成分を読む, 文字列を読む};

/// 正解表がどの組み立てのものかを言うキー。木の表がこの綴りを使う。
const 組み立てのキー: &str = "組み立てID";

/// 同じ意味の古い綴り。酒場宿屋の表がまだこれを使っている。**両方を受け取るのはこの1箇所だけであり、
/// 読み取った先はどちらで書かれていたかを知らない。** 綴りが2つに割れていること自体はBlender側と揃えて
/// 解消する事柄であり、それまで表を読めないままにすると突き合わせが止まる。
const 旧い建物のキー: &str = "建物ID";
const 座標系のキー: &str = "座標系";
const 姿勢一覧のキー: &str = "部品の姿勢";
const 部品のキー: &str = "部品ID";
const 平行移動のキー: &str = "平行移動";
const 回転のキー: &str = "回転";
const 倍率のキー: &str = "倍率";

/// この読み手が受け取る座標系。接合点の契約と同じくglTF(Yが上)である。
const 受け取る座標系: &str = "glTF";

pub struct 組み立ての正解表のファイル {
    パス: PathBuf,
}

impl 組み立ての正解表のファイル {
    pub fn 生成する(パス: &Path) -> Self {
        Self {
            パス: パス.to_path_buf()
        }
    }

    pub fn 正解表を読み取る(&self) -> Result<正解表, 正解表の読み込みエラー> {
        let 綴り = std::fs::read_to_string(&self.パス).map_err(|誤り| 正解表の読み込みエラー::ファイルを読めない {
            パス: self.パス.display().to_string(),
            誤り,
        })?;
        let 本体: Value =
            serde_json::from_str(&綴り).map_err(|誤り| 正解表の読み込みエラー::正解表のJSONを解けない(誤り.to_string()))?;
        座標系を確かめる(&本体)?;
        let 組み立て = 組み立ての識別子を読む(&本体)?;
        let 姿勢の配列 = 本体
            .get(姿勢一覧のキー)
            .ok_or(正解表の読み込みエラー::キーが無い {
                キー名: 姿勢一覧のキー
            })?
            .as_array()
            .ok_or(正解表の読み込みエラー::値の形が違う {
                キー名: 姿勢一覧のキー
            })?;
        let mut 姿勢一覧 = Vec::with_capacity(姿勢の配列.len());
        for 項目 in 姿勢の配列 {
            姿勢一覧.push(姿勢1件を読む(項目)?);
        }
        Ok(正解表::組み立てと姿勢から生成する(組み立て.to_string(), 姿勢一覧))
    }
}

fn 座標系を確かめる(本体: &Value) -> Result<(), 正解表の読み込みエラー> {
    let 綴り = 文字列を読む(本体, 座標系のキー)?;
    if 綴り == 受け取る座標系 {
        return Ok(());
    }
    Err(正解表の読み込みエラー::座標系がglTFでない { 綴り: 綴り.to_string() })
}

fn 姿勢1件を読む(項目: &Value) -> Result<正解の姿勢, 正解表の読み込みエラー> {
    Ok(正解の姿勢 {
        部品の識別子: 文字列を読む(項目, 部品のキー)?.to_string(),
        平行移動: 三成分を読む(項目, 平行移動のキー)?,
        回転: 四成分を読む(項目, 回転のキー)?,
        倍率: 三成分を読む(項目, 倍率のキー)?,
    })
}

/// 組み立ての識別子を読む。現行の綴りが無ければ古い綴りを見る。**どちらも無いときは現行の綴りで報告する。**
/// 古い綴りの名前を失敗の文面へ出すと、新しく書く表がどちらを使えばよいのか読み手に決められない。
fn 組み立ての識別子を読む(本体: &Value) -> Result<String, 正解表の読み込みエラー> {
    if 本体.get(組み立てのキー).is_none() && 本体.get(旧い建物のキー).is_some() {
        return Ok(文字列を読む(本体, 旧い建物のキー)?.to_string());
    }
    Ok(文字列を読む(本体, 組み立てのキー)?.to_string())
}
