//! 正解表のJSONの値の読み取り。担当するのは、キーを指定して文字列と3成分と4成分を型ガードつきで取り出すことである。
//!
//! 何が正解表かを持つ側から、JSONの値をどう読むかを持つ側を分ける。表のキーが増えてもこの工程は変わらない。
//!
//! 数はf64を経由して狭めず、綴られた十進表記をそのままf32として解く。標準ライブラリがf64からf32への
//! 型付き変換を持たず、`as`による縮小変換をリポジトリの規約が禁じているためである。接合点の読みと同じ理由である。

use serde_json::Value;

use super::error::正解表の読み込みエラー;

pub(super) fn 文字列を読む<'値>(本体: &'値 Value, キー名: &'static str) -> Result<&'値 str, 正解表の読み込みエラー> {
    本体
        .get(キー名)
        .ok_or(正解表の読み込みエラー::キーが無い { キー名 })?
        .as_str()
        .ok_or(正解表の読み込みエラー::値の形が違う { キー名 })
}

pub(super) fn 三成分を読む(本体: &Value, キー名: &'static str) -> Result<[f32; 3], 正解表の読み込みエラー> {
    let 読んだ = 成分列を読む(本体, キー名, 3)?;
    Ok([読んだ[0], 読んだ[1], 読んだ[2]])
}

pub(super) fn 四成分を読む(本体: &Value, キー名: &'static str) -> Result<[f32; 4], 正解表の読み込みエラー> {
    let 読んだ = 成分列を読む(本体, キー名, 4)?;
    Ok([読んだ[0], 読んだ[1], 読んだ[2], 読んだ[3]])
}

fn 成分列を読む(本体: &Value, キー名: &'static str, 期待する件数: usize) -> Result<Vec<f32>, 正解表の読み込みエラー> {
    let 配列 = 本体
        .get(キー名)
        .ok_or(正解表の読み込みエラー::キーが無い { キー名 })?
        .as_array()
        .ok_or(正解表の読み込みエラー::値の形が違う { キー名 })?;
    if 配列.len() != 期待する件数 {
        return Err(正解表の読み込みエラー::値の形が違う { キー名 });
    }
    配列.iter().map(|値| 数として解く(値, キー名)).collect()
}

fn 数として解く(値: &Value, キー名: &'static str) -> Result<f32, 正解表の読み込みエラー> {
    let Value::Number(数) = 値 else {
        return Err(正解表の読み込みエラー::値の形が違う { キー名 });
    };
    数.to_string()
        .parse::<f32>()
        .ok()
        .filter(|解いた| 解いた.is_finite())
        .ok_or(正解表の読み込みエラー::値の形が違う { キー名 })
}
