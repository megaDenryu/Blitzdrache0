//! 部品で組んだ個体を散らすときの失敗。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! アセットコンパイルエラーへ直に枝を足さずこの型を挟むのは、散布だけが持つ前提(規則が指す部品と接合点が
//! 宣言に在ること)を1箇所へ集めるためである。並びのコンパイルエラーと同じ形であり、上位の型は`#[from]`で
//! 1枝だけを持つ。

use blitz_assembly::展開エラー;
use thiserror::Error;

#[derive(Debug, Error)]
pub enum 部品で組んだ散布のコンパイルエラー {
    /// 規則が指す部品や接合点が宣言に無いか、噛み合わない組を指している。何体目で落ちたかを添えるのは、
    /// 個体ごとに種が違い、特定の種でだけ選ばれる候補が破れることがあるためである。
    #[error("散らした{個体の番号}体目を規則で展開できない: {誤り}")]
    個体を展開できない {
        個体の番号: usize,
        #[source]
        誤り: 展開エラー,
    },
}
