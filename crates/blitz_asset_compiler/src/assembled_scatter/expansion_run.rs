//! 部品で組む散布の展開係: 部品カタログと展開の種の起点を保持し、根の配置列を1つの集約へまとめる操作サービス。
//!
//! 展開器と種の起点を保持するのは、この2つが1つの種を散らすあいだ変わらないためである。個体ごとに引数で渡すと、
//! 別のカタログと別の種の起点を組み合わせた呼び出しが型を通る。
//!
//! **集約がここで作られることが、描画対象の数が本数に比例しないことの実装である。** 個体ごとに出た配置表を
//! 部品の種類ごとの1つの配置列へ畳むため、本数が増えても描画対象の数は変わらない。
//! 並びの展開係と同じ形であり、違うのは根の配置を敷地でなく散布の走査から受け取ることだけである。

use blitz_assembly::{展開器, 生成の種, 組み立て規則, 部品ごとの配置の集約, 部品カタログ};
use blitz_engine::個体配置;

use super::error::部品で組んだ散布のコンパイルエラー;
use crate::error::アセットコンパイルエラー;

pub(super) struct 部品で組む散布の展開係 {
    展開器: 展開器,
    種の起点: 生成の種,
}

impl 部品で組む散布の展開係 {
    pub(super) fn 生成する(カタログ: 部品カタログ, 種の起点: 生成の種) -> Self {
        Self {
            展開器: 展開器::カタログを持たせて生成する(カタログ),
            種の起点,
        }
    }

    /// 根の配置1件ごとに種を分けて展開し、部品の種類ごとの配置列へまとめる。
    /// 種を根の番号で分けるのは、同じ種のままだと1本残らず同じ姿になり、組み合わせで違いを作る設計が絵に出ないためである。
    pub(super) fn 根の配置列を展開する(
        &self,
        規則: &組み立て規則,
        根の配置一覧: &[個体配置],
    ) -> Result<部品ごとの配置の集約, アセットコンパイルエラー> {
        let mut 集約 = 部品ごとの配置の集約::空から始める();
        for (番号, 根の配置) in 根の配置一覧.iter().enumerate() {
            let 種 = self.種の起点.個体の番号で分けた種を作る(番号を混合へ写す(番号));
            let 配置表 = self.展開器.規則から展開する(規則, 種, *根の配置).map_err(|誤り| {
                部品で組んだ散布のコンパイルエラー::個体を展開できない {
                    個体の番号: 番号, 誤り
                }
            })?;
            集約.配置表を1件取り込む(&配置表);
        }
        Ok(集約)
    }
}

/// 走査の番号を混合へ入れる値へ写す。件数はu16の範囲を出ないことを散布の指定の検証が保つため、
/// この変換で値が落ちることはない。
fn 番号を混合へ写す(番号: usize) -> u64 {
    u64::try_from(番号).unwrap_or(u64::MAX)
}
