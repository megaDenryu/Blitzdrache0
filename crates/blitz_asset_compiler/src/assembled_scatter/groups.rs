//! 部品ごとの配置の集約から、部品の種類ごとの群の描画対象を作る工程。受け取るのは集約と部品一式と先頭の描画対象番号、
//! 返すのは群の一覧と、置いた個体の数と、原型が読んだファイルの一覧である。
//!
//! 描画対象番号を先頭から受け取るのは、番号がシーン全体で一意でなければならず、この工程が知っているのは
//! 自分の群の並びだけだからである。配る規律(1つ作るごとに1つ進める)はここが持つ。
//!
//! 群の共有マテリアルは部品のglTFが宣言したものをそのまま使う。部品は材質スロットごとにプリミティブへ分かれ、
//! 色は作った本人がベースカラー係数で与えているため、コンパイラが選び直すと作者の宣言と絵が食い違う。

use std::path::PathBuf;

use blitz_assembly::部品ごとの配置の集約;
use blitz_engine::{チャンク座標, 描画対象データ};

use crate::assembly_parts::組み立てに使う部品一式;
use crate::error::アセットコンパイルエラー;
use crate::placed_instance_count::置いた個体の数;
use crate::scene_compiler::ソースアセットのコンパイル係;
use crate::vegetation::group_object;

/// 1つの散らす種が作った群の一覧。描画対象の数は部品の種類の数であり、散らした本数ではない。
pub(crate) struct 部品ごとの群一覧 {
    描画対象一覧: Vec<描画対象データ>,
    置いた個体の数: 置いた個体の数,
    参照ファイル一覧: Vec<PathBuf>,
}

impl 部品ごとの群一覧 {
    pub(crate) fn 置いた個体の数(&self) -> 置いた個体の数 {
        self.置いた個体の数
    }

    /// 群と参照ファイルを取り出して閉じる。以降この一覧は使えない。
    pub(crate) fn 描画対象と参照ファイルへ畳む(self) -> (Vec<描画対象データ>, Vec<PathBuf>) {
        (self.描画対象一覧, self.参照ファイル一覧)
    }
}

/// 集約の項目1つにつき群を1つ作る。項目の並びは最初に現れた順であり、同じ入力から同じ実行時形式のバイト列を得る。
pub(crate) fn 集約から群を作る(
    コンパイル係: &ソースアセットのコンパイル係<'_>,
    所有チャンク: チャンク座標,
    先頭の描画対象番号: u64,
    部品一式: &組み立てに使う部品一式,
    集約: &部品ごとの配置の集約,
) -> Result<部品ごとの群一覧, アセットコンパイルエラー> {
    let mut 一覧 = 部品ごとの群一覧 {
        描画対象一覧: Vec::with_capacity(集約.部品の種類数()),
        置いた個体の数: 置いた個体の数::零(),
        参照ファイル一覧: Vec::new(),
    };
    let mut 描画対象番号 = 先頭の描画対象番号;
    for 項目 in 集約.項目一覧() {
        let 原型 = コンパイル係.部品の原型ソースを読み込む(部品一式.原型の安定idを引く(項目.識別子())?)?;
        let 群 = group_object::群の描画対象を作る(描画対象番号, 所有チャンク, 原型.段一覧, 原型.材質集合, 項目.配置一覧().to_vec())?;
        描画対象番号 += 1;
        一覧.置いた個体の数 = 一覧.置いた個体の数.足す(群.置いた個体の数)?;
        一覧.参照ファイル一覧.extend(原型.参照ファイル一覧);
        一覧.描画対象一覧.push(群.描画対象);
    }
    Ok(一覧)
}
