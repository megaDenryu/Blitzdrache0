//! 集落へ散らす小物1種の配置列を決める工程。受け取るのは所有チャンクと種の通し番号と個体数と様式と地表高さを返す関数、
//! 返すのはチャンクアンカー相対の配置列である。
//!
//! 走査順は添字の昇順に固定し、値はチャンク座標と種の通し番号と添字だけから決まる混合関数で作るため、
//! 同じ宣言からは常に同じ配置列を得る。種の通し番号を混ぜるのは、様式と個体数が同じ2つの種が
//! 同じ並びになると、同じ場所に別の小物が重なって立つためである。
//!
//! 平行移動のYを地表高さにするのは、小物の原型が接地面をy=0に持ち、その値がそのまま接地面になるためである。

use blitz_engine::{チャンク座標, 個体配置};

use super::layout::{self, 水平配置};
use crate::error::アセットコンパイルエラー;
use crate::vegetation::deterministic_value::{用途, 零以上一未満};

/// 個体の大きさの範囲。小物はすでに実測寸法で作られているため、倍率は個体差を作るぶんだけに留める。
const 大きさの下限: f32 = 0.9;
const 大きさの上限: f32 = 1.12;

/// 混合関数の固定の種。世界を変えない限り同じ値を使い、同じ宣言から同じバイト列を得る。
const 種: u64 = 0x5669_6C6C_6167_6531;

/// 配置の添字をu16で扱うため、1種あたりの個体数はこの値までとする。
const 個体数の上限: usize = 65_535;

/// 小物1種をどう並べるか。様式ごとに位置の決め方と向きの決め方が違うため、判別共用体で持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 配置様式 {
    /// 集落の中心を囲む輪に沿って並べ、個体を輪の接線へ向ける。長手方向を持つ柵と石垣に充てる。
    輪に沿う {
        半径メートル: f32, ばらつきメートル: f32
    },
    /// 指定した点のまわりの円板へ集める。人が使う場所へ寄せて置かれる荷や器に充てる。
    集まり {
        中心xメートル: f32,
        中心zメートル: f32,
        半径メートル: f32,
    },
    /// 集落の中心を中心とする正方領域へ格子状に散らす。人の都合と関わりなく地面にある岩や切り株に充てる。
    一様に散らす { 一辺メートル: f32 },
}

pub(super) fn 配置列を作る(
    所有チャンク: チャンク座標,
    種の通し番号: u64,
    個体数: usize,
    様式: 配置様式,
    地表高さを求める: impl Fn(f32, f32) -> Result<f32, アセットコンパイルエラー>,
) -> Result<Vec<個体配置>, アセットコンパイルエラー> {
    if 個体数 == 0 || 個体数 > 個体数の上限 {
        return Err(アセットコンパイルエラー::植生個体数不正(個体数));
    }
    let 個体数u16 = u16::try_from(個体数).map_err(|_| アセットコンパイルエラー::植生個体数不正(個体数))?;
    let 群の種 = 種 ^ 所有チャンク.番号を返す() ^ 種の通し番号.wrapping_mul(0x9E37_79B9_7F4A_7C15);
    let mut 配置一覧 = Vec::with_capacity(個体数);
    for 添字 in 0..個体数u16 {
        let 水平 = 水平位置を求める(様式, 群の種, 添字, 個体数u16);
        let 向き = 水平.向きラジアン.unwrap_or_else(|| 自由な向きを決める(群の種, 添字));
        let 倍率 = 大きさの下限 + (大きさの上限 - 大きさの下限) * 零以上一未満(群の種, u64::from(添字), 用途::大きさ);
        let 高さ = 地表高さを求める(水平.x, 水平.z)?;
        配置一覧.push(個体配置::生成する([水平.x, 高さ, 水平.z], y軸回転を作る(向き), [倍率; 3])?);
    }
    Ok(配置一覧)
}

fn 水平位置を求める(様式: 配置様式, 群の種: u64, 添字: u16, 個体数: u16) -> 水平配置 {
    match 様式 {
        配置様式::輪に沿う {
            半径メートル,
            ばらつきメートル,
        } => layout::輪の配置(群の種, 添字, 個体数, 半径メートル, ばらつきメートル),
        配置様式::集まり {
            中心xメートル,
            中心zメートル,
            半径メートル,
        } => layout::集まりの配置(群の種, 添字, 中心xメートル, 中心zメートル, 半径メートル),
        配置様式::一様に散らす { 一辺メートル } => layout::格子の配置(群の種, 添字, 個体数, 一辺メートル),
    }
}

/// 様式が向きを定めないときの向き。全周から選ぶ。
fn 自由な向きを決める(群の種: u64, 添字: u16) -> f32 {
    零以上一未満(群の種, u64::from(添字), 用途::向き) * std::f32::consts::TAU
}

/// Y軸まわりの回転だけを作る。小物は地面に立つため、傾ける自由度をこの段では持たせない。
fn y軸回転を作る(角度: f32) -> [f32; 4] {
    let 半角 = 角度 * 0.5;
    [0.0, 半角.sin(), 0.0, 半角.cos()]
}
