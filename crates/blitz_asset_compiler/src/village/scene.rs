//! 見本の集落のシーンを組み立てる工程。受け取るのはカタログと高さ格子と所有チャンクと小物の群の宣言、
//! 返すのは地面1つと群を種の数だけ持つシーンデータである。
//!
//! 地面を地形LODメッシュ群として焼くのは、地形の世界と同じ経路で焼くことで、小物の接地が
//! 描画される面と同じ求め方の上に乗るためである。地表高さは最詳細段が張る三角形の平面から引く。

use std::path::PathBuf;

use blitz_engine::{
    カタログ, シーンデータ, チャンク座標, マテリアルデータ, 描画対象ID, 描画対象データ, 描画形状, 材質集合, 金属粗さPBRデータ
};

use super::prop_group::小物群の描画対象を作る;
use super::小物群の指定;
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子;
use crate::terrain::lod_bake;
use crate::vegetation::group_object;

/// 地面の描画対象番号。1つの高さ格子が1つの描画対象になるため常にこの値であり、群はこの次から番号を取る。
const 地面の描画対象番号: u64 = 0;

pub(super) fn 組み立てる(
    カタログ: &カタログ,
    格子: &高さ格子,
    所有チャンク: チャンク座標,
    ソースパス: PathBuf,
    群一覧: &[小物群の指定],
) -> Result<シーンデータ, アセットコンパイルエラー> {
    if 群一覧.is_empty() {
        return Err(アセットコンパイルエラー::見本の集落に群が無い);
    }
    let 地面 = 描画対象データ::生成する(
        描画対象ID::生成する(地面の描画対象番号),
        所有チャンク,
        group_object::恒等変換を作る(),
        描画形状::地形LODメッシュ群(lod_bake::段別メッシュを焼く(格子)?),
        材質集合::単一材質から生成する(地面のマテリアルを作る()),
    );
    let mut 参照ファイル一覧 = vec![ソースパス];
    let mut 群の描画対象一覧 = Vec::with_capacity(群一覧.len());
    let mut 通し番号 = 地面の描画対象番号;
    for 指定 in 群一覧 {
        通し番号 += 1;
        let (対象, 参照一覧) = 小物群の描画対象を作る(カタログ, 格子, 所有チャンク, 通し番号, 指定)?;
        参照ファイル一覧.extend(参照一覧);
        群の描画対象一覧.push(対象);
    }
    Ok(シーンデータ::生成する(
        地面,
        群の描画対象一覧,
        参照ファイル一覧,
        None,
        Vec::new(),
    ))
}

/// 地面は土の色の非金属として描く。地形の世界が白いのは植生の緑と画素で見分けるためであり、
/// 集落は絵として見る世界であるから、小物の木と石が乗って自然に見える色を選ぶ。
fn 地面のマテリアルを作る() -> マテリアルデータ {
    マテリアルデータ::金属粗さPBR(金属粗さPBRデータ {
        ベースカラー: None,
        金属粗さ: None,
        法線マップ: None,
        ベースカラー係数: [0.38, 0.35, 0.27, 1.0],
        金属度係数: 0.0,
        粗さ係数: 0.95,
    })
}
