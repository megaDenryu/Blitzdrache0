//! 小物1種のインスタンス群を1つの描画対象へ作る工程。受け取るのは地面の高さ格子と所有チャンクと描画対象番号と群の指定、
//! 返すのは描画対象と原型が参照したファイルの一覧である。
//!
//! 群の共有マテリアルは原型のglTFが宣言したものをそのまま使う。小物は種ごとに色が違い、その色は生成した本人が
//! ベースカラー係数で与えているため、コンパイラが選び直すと作者の宣言と絵が食い違う。
//! 植生の同居がマテリアルを選び直すのは、原型ソースが既定の白のままで地形と画素で見分けられないからであり、
//! こちらにはその事情が無い。

use std::path::PathBuf;

use blitz_engine::{チャンク座標, 描画対象データ};

use super::placement;
use super::小物群の指定;
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子;
use crate::scene_compiler::ソースアセットのコンパイル係;
use crate::terrain::ground_height;
use crate::vegetation::group_object;

impl ソースアセットのコンパイル係<'_> {
    pub(crate) fn 小物群の描画対象を作る(
        &self,
        格子: &高さ格子,
        所有チャンク: チャンク座標,
        描画対象番号: u64,
        指定: &小物群の指定,
    ) -> Result<(描画対象データ, Vec<PathBuf>), アセットコンパイルエラー> {
        let 原型ソース = self.原型ソースを読み込む(&指定.原型id)?;
        let 配置一覧 = placement::配置列を作る(所有チャンク, 描画対象番号, 指定.個体数, 指定.配置様式, |x, z| {
            ground_height::地表高さを求める(格子, x, z)
        })?;
        let 対象 = group_object::群の描画対象を作る(描画対象番号, 所有チャンク, 原型ソース.段一覧, 原型ソース.材質集合, 配置一覧)?;
        Ok((対象, 原型ソース.参照ファイル一覧))
    }
}
