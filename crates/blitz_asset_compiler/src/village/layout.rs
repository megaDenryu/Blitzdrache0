//! 配置様式ごとの水平位置と向きの決め方。受け取るのは様式と混合の種と個体の添字、
//! 返すのはチャンクアンカー相対の水平位置と、様式が向きを定めるならその向きである。
//! 高さと大きさと走査の組み立ては`placement`が持ち、ここは水平の並べ方だけを持つ。
//!
//! 添字と個体数をu16で受け取るのは、範囲の検査を`placement`が入口で1回だけ済ませているためである。
//! ここで再び範囲を疑うと、同じ条件を2箇所が持つことになる。

use crate::vegetation::deterministic_value::{用途, 零以上一未満};

/// 集落の中心。チャンクの大域原点はX最小・Z最小の角にあるため、一辺100メートルの半分だけ内側がチャンクの中央になる。
pub(super) const 集落の中心メートル: f32 = 50.0;

/// 格子の刻みに対する揺らぎの比率。格子らしさを消しつつ、隣り合う個体が重なり合わない幅に留める。
const 格子の揺らぎ比率: f32 = 0.18;

/// 輪に並べるときに1個体が受け持つ角度に対する揺らぎの比率。並びの機械らしさを消す。
const 輪の角度揺らぎ比率: f32 = 0.3;

/// 水平位置と、様式が定める向き。向きを定めない様式は`None`を返し、呼び出し側が自由な向きを与える。
pub(super) struct 水平配置 {
    pub(super) x: f32,
    pub(super) z: f32,
    pub(super) 向きラジアン: Option<f32>,
}

/// 中心を囲む輪に沿って等間隔に並べ、個体を輪の接線へ向ける。柵や石垣が連なった囲いとして読み取れる並びになる。
///
/// 向きは、Y軸まわりの回転が原型の局所+X軸を(cos角, 0, -sin角)へ写すことから決まる。輪の接線は
/// 角度θの点で(-sinθ, cosθ)であるため、この2つを等しくする角は-(π/2 + θ)である。
/// 原型の長手方向が局所X軸であることが前提であり、柵と石垣はどちらもX方向に長い。
pub(super) fn 輪の配置(種: u64, 添字: u16, 個体数: u16, 半径: f32, ばらつき: f32) -> 水平配置 {
    let 添字u64 = u64::from(添字);
    let 一区画の角度 = std::f32::consts::TAU / f32::from(個体数);
    let 揺らぎ = (零以上一未満(種, 添字u64, 用途::周方向の揺らぎ) * 2.0 - 1.0) * 輪の角度揺らぎ比率;
    let 角度 = (f32::from(添字) + 揺らぎ) * 一区画の角度;
    let 実半径 = 半径 + (零以上一未満(種, 添字u64, 用途::半径方向の揺らぎ) * 2.0 - 1.0) * ばらつき;
    水平配置 {
        x: 集落の中心メートル + 実半径 * 角度.cos(),
        z: 集落の中心メートル + 実半径 * 角度.sin(),
        向きラジアン: Some(-(std::f32::consts::FRAC_PI_2 + 角度)),
    }
}

/// 指定した点のまわりの円板へ集める。半径に平方根を掛けるのは、そうしないと個体が中心へ偏り、
/// 荷を置いた場所でなく1点へ積み上げた山に見えるためである。
pub(super) fn 集まりの配置(種: u64, 添字: u16, 中心x: f32, 中心z: f32, 半径: f32) -> 水平配置 {
    let 添字u64 = u64::from(添字);
    let 実半径 = 半径 * 零以上一未満(種, 添字u64, 用途::半径方向の揺らぎ).sqrt();
    let 角度 = 零以上一未満(種, 添字u64, 用途::周方向の揺らぎ) * std::f32::consts::TAU;
    水平配置 {
        x: 中心x + 実半径 * 角度.cos(),
        z: 中心z + 実半径 * 角度.sin(),
        向きラジアン: None,
    }
}

/// 正方領域へ格子状に散らし、格子の刻みに対する割合で揺らす。人の都合と関わりなく地面にあるものへ充てる。
pub(super) fn 格子の配置(種: u64, 添字: u16, 個体数: u16, 一辺: f32) -> 水平配置 {
    let 添字u64 = u64::from(添字);
    let 列数 = 正方格子の列数(個体数);
    let 刻み = 一辺 / f32::from(列数);
    let 中心添字 = (f32::from(列数) - 1.0) * 0.5;
    水平配置 {
        x: 格子座標(f32::from(添字 % 列数), 中心添字, 刻み, 零以上一未満(種, 添字u64, 用途::X方向の揺らぎ)),
        z: 格子座標(f32::from(添字 / 列数), 中心添字, 刻み, 零以上一未満(種, 添字u64, 用途::Z方向の揺らぎ)),
        向きラジアン: None,
    }
}

fn 格子座標(添字: f32, 中心添字: f32, 刻み: f32, 揺らぎ: f32) -> f32 {
    集落の中心メートル + (添字 - 中心添字) * 刻み + (揺らぎ * 2.0 - 1.0) * 刻み * 格子の揺らぎ比率
}

/// 個体数を覆う最小の正方格子の列数。個体数がu16に収まることは入口が検査済みであり、
/// 列数はその平方根以下であるため、この繰り返しはu16の範囲で止まる。
fn 正方格子の列数(個体数: u16) -> u16 {
    let mut 列数 = 1_u16;
    while u32::from(列数) * u32::from(列数) < u32::from(個体数) {
        列数 += 1;
    }
    列数
}
