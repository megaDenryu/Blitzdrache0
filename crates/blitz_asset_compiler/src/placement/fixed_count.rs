//! 個体数を決めてから並べる並べ方と、その配置列を作る工程。受け取るのは高さ格子と群の種と並べ方、
//! 返すのはチャンクの基準原点からの相対の配置列である。
//!
//! 個体数をこの並べ方の側が持つのは、密度場で散らす様式が個体数を宣言せず密度から決めるためである。
//! 個体数を様式の外へ置くと、密度場の様式が読まない値を宣言に書かせることになる。
//!
//! 走査順は添字の昇順に固定し、値は群の種と添字だけから決まる混合関数で作るため、同じ宣言からは常に同じ配置列を得る。

use blitz_engine::個体配置;

use super::deterministic_value::{用途, 零以上一未満};
use super::layout;
use super::layout::水平配置;
use super::orientation::天頂まわりの回転を作る;
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子;
use crate::terrain::ground_height;

/// 個体の大きさの範囲。小物はすでに実測寸法で作られているため、倍率は個体差を作るぶんだけに留める。
const 大きさの下限: f32 = 0.9;
const 大きさの上限: f32 = 1.12;

/// 配置の添字をu16で扱うため、1種あたりの個体数はこの値までとする。
const 個体数の上限: usize = 65_535;

/// 個体数を決めてから並べる並べ方。並べ方ごとに位置の決め方と向きの決め方が違うため、判別共用体で持つ。
///
/// `輪に沿う`はチャンクの中央を囲む輪に沿って並べ、輪の接線へ向ける。柵と石垣に充てる。
/// `集まり`は指定した点のまわりの円板へ集める。荷や器に充てる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 個数を決める並べ方 {
    輪に沿う {
        個体数: usize,
        半径メートル: f32,
        ばらつきメートル: f32,
    },
    集まり {
        個体数: usize,
        中心xメートル: f32,
        中心zメートル: f32,
        半径メートル: f32,
    },
    一様に散らす {
        個体数: usize,
        一辺メートル: f32,
    }, // 中央を中心とする正方領域へ格子状に散らす。岩や切り株に充てる
}

impl 個数を決める並べ方 {
    fn 個体数(self) -> usize {
        match self {
            Self::輪に沿う { 個体数, .. } | Self::集まり { 個体数, .. } | Self::一様に散らす { 個体数, .. } => 個体数,
        }
    }
}

pub(super) fn 個数を決めて並べた配置列を作る(
    格子: &高さ格子,
    群の種: u64,
    並べ方: 個数を決める並べ方,
) -> Result<Vec<個体配置>, アセットコンパイルエラー> {
    let 個体数 = 並べ方.個体数();
    if 個体数 == 0 || 個体数 > 個体数の上限 {
        return Err(アセットコンパイルエラー::植生個体数不正(個体数));
    }
    let 個体数u16 = u16::try_from(個体数).map_err(|_| アセットコンパイルエラー::植生個体数不正(個体数))?;
    let mut 配置一覧 = Vec::with_capacity(個体数);
    for 添字 in 0..個体数u16 {
        let 水平 = 水平位置を求める(並べ方, 群の種, 添字, 個体数u16);
        let 向き = 水平.向きラジアン.unwrap_or_else(|| 自由な向きを決める(群の種, 添字));
        let 倍率 = 大きさの下限 + (大きさの上限 - 大きさの下限) * 零以上一未満(群の種, u64::from(添字), 用途::大きさ);
        let 高さ = ground_height::地表高さを求める(格子, 水平.x, 水平.z)?;
        配置一覧.push(個体配置::生成する(
            [水平.x, 高さ, 水平.z],
            天頂まわりの回転を作る(向き),
            [倍率; 3],
        )?);
    }
    Ok(配置一覧)
}

fn 水平位置を求める(並べ方: 個数を決める並べ方, 群の種: u64, 添字: u16, 個体数: u16) -> 水平配置 {
    match 並べ方 {
        個数を決める並べ方::輪に沿う {
            半径メートル,
            ばらつきメートル,
            ..
        } => layout::輪の配置(群の種, 添字, 個体数, 半径メートル, ばらつきメートル),
        個数を決める並べ方::集まり {
            中心xメートル,
            中心zメートル,
            半径メートル,
            ..
        } => layout::集まりの配置(群の種, 添字, 中心xメートル, 中心zメートル, 半径メートル),
        個数を決める並べ方::一様に散らす { 一辺メートル, .. } => layout::格子の配置(群の種, 添字, 個体数, 一辺メートル),
    }
}

/// 並べ方が向きを定めないときの向き。全周から選ぶ。
fn 自由な向きを決める(群の種: u64, 添字: u16) -> f32 {
    零以上一未満(群の種, u64::from(添字), 用途::向き) * std::f32::consts::TAU
}
