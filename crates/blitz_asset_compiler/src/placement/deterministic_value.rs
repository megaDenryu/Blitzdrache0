//! 散布が使う用途の区別と、混合関数への入口。担当するのは用途に番号を割り当てることだけである。
//!
//! 混合そのものは`blitz_math`が1つだけ持つ。部品の展開(`blitz_assembly`)も同じ混合を使うため、
//! ここが写しを持つと、同じ種から違う配置が出る形の食い違いが生まれる。
//!
//! 注意: **番号を変えると焼いた配置が全部変わる。** 既存の検収の判定値はこの番号の割り当てに依存している。

use blitz_math::{決定的な値の生成器, 用途番号};

/// 用途の識別。同じ添字から複数の独立した値を得るため、用途ごとに混合の入力を変える。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 用途 {
    X方向の揺らぎ,
    Z方向の揺らぎ,
    向き,
    大きさ,
    周方向の揺らぎ,
    半径方向の揺らぎ,
    出現, // その走査の区画へ個体を置くかどうかの判定
}

impl 用途 {
    fn 番号(self) -> 用途番号 {
        用途番号::番号から生成する(match self {
            Self::X方向の揺らぎ => 1,
            Self::Z方向の揺らぎ => 2,
            Self::向き => 3,
            Self::大きさ => 4,
            Self::周方向の揺らぎ => 5,
            Self::半径方向の揺らぎ => 6,
            Self::出現 => 7,
        })
    }
}

pub(crate) fn 零以上一未満(種: u64, 添字: u64, 用途: 用途) -> f32 {
    決定的な値の生成器::種の値から生成する(種).零以上一未満(添字, 用途.番号())
}
