//! 世界大域の密度場と地表の傾きで、置く置かないを走査の区画ごとに決める工程。受け取るのは高さ格子と所有チャンクと
//! 群の種と配置の種と散布の指定、返すのはチャンクの基準原点からの相対の配置列である。
//!
//! 密度場を大域サンプル添字で引くのは、隣り合うチャンクが同じ添字で同じ値を引き、森と草原の塊が
//! チャンクの境目で途切れないためである。チャンク座標だけを種に混ぜる形では、どのチャンクも同じ密度になり、
//! 世界のどこを見ても同じ密度で物が生える。
//!
//! 置く置かないの判定に三角関数も平方根も通さないのは、超越関数の近似が処理系ごとに違い、境目の候補が
//! 別の機材では逆の判定になって個体数が変わるためである。個体数が変われば実行時形式のバイト列が変わる。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「判断j」

