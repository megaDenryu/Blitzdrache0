/// 走査の区画の一辺に対する揺らぎの比率。区画の中心から動かせる幅は半分であるため、1未満なら区画の外へ出ない。
/// 区画の外へ出さないのは、チャンクの縁を越えた個体が隣のチャンクの地面へめり込むためである。
const 区画の揺らぎ比率: f32 = 0.8;

pub(super) fn 密度場で散らした配置列を作る(
    格子: &高さ格子,
    所有チャンク: チャンク座標,
    群の種: u64,
    配置の種: 配置の種,
    指定: 密度場の散布,
) -> Result<Vec<個体配置>, アセットコンパイルエラー> {
    指定.検証する()?;
    let 諸元 = 格子.諸元();
    let 列数 = u16::from(指定.走査の列数);
    let 区画のメートル = 諸元.一辺メートル() / f32::from(列数);
    let 密度場の種 = 配置の種.密度場の種(指定.密度場.層のずらし);
    let mut 配置一覧 = Vec::new();
    for 行 in 0..列数 {
        for 列 in 0..列数 {
            let 添字 = u64::from(行) * u64::from(列数) + u64::from(列);
            let 中心x = (f32::from(列) + 0.5) * 区画のメートル;
            let 中心z = (f32::from(行) + 0.5) * 区画のメートル;
            let 大域x = 大域サンプル添字を求める(所有チャンク.x(), 諸元.辺分割数(), 中心x / 諸元.刻みメートル())?;
            let 大域z = 大域サンプル添字を求める(所有チャンク.z(), 諸元.辺分割数(), 中心z / 諸元.刻みメートル())?;
            let 密度場の値 = 格子雑音の値(密度場の種, 大域x, 大域z, 指定.密度場.升目の標本数);
            if 零以上一未満(群の種, 添字, 用途::出現) >= 指定.出現の割合.密度場の値から求める(密度場の値) {
                continue;
            }
            let x = 中心x + 揺らぎ(群の種, 添字, 用途::X方向の揺らぎ, 区画のメートル);
            let z = 中心z + 揺らぎ(群の種, 添字, 用途::Z方向の揺らぎ, 区画のメートル);
            let 面 = ground_height::地表の面を求める(格子, x, z)?;
            if !指定.傾きの好み.受け入れるか(&面) {
                continue;
            }
            let 天頂まわりの角度 = 零以上一未満(群の種, 添字, 用途::向き) * std::f32::consts::TAU;
            let 回転 = match 指定.据え方 {
                地表への据え方::垂直に立てる => 天頂まわりの回転を作る(天頂まわりの角度),
                地表への据え方::地表法線へ倒す => 地表法線へ倒した回転を作る(&面, 天頂まわりの角度),
            };
            let 倍率 = 指定.大きさの範囲.零以上一未満の値から求める(零以上一未満(群の種, 添字, 用途::大きさ));
            配置一覧.push(個体配置::生成する([x, 面.高さメートル(), z], 回転, [倍率; 3])?);
        }
    }
    Ok(配置一覧)
}

/// 区画の中心からの揺らぎ。区画の一辺の半分に比率を掛けた幅で、正負の両側へ動かす。
fn 揺らぎ(群の種: u64, 添字: u64, 用途: 用途, 区画のメートル: f32) -> f32 {
    (零以上一未満(群の種, 添字, 用途) * 2.0 - 1.0) * 区画のメートル * 0.5 * 区画の揺らぎ比率
}

/// 局所の格子添字を大域サンプル添字へ写す。i16へ収まらない要求は無言で丸めず型付きエラーにする。
/// 収まらないのは世界が大域サンプル添字の範囲より広い場合であり、高さ格子の切り出しと同じ境界である。
fn 大域サンプル添字を求める(
    チャンク成分: i32, 辺分割数: u16, 局所の格子添字: f32
) -> Result<i16, アセットコンパイルエラー> {
    let 床 = 局所の格子添字.floor();
    let 収まる = 床 < f32::from(辺分割数);
    let 局所 = 負でない床をu16にする(床)
        .filter(|_| 収まる)
        .map(i32::from)
        .ok_or(アセットコンパイルエラー::地表高さの座標範囲外(局所の格子添字))?;
    let 合計 = チャンク成分
        .checked_mul(i32::from(辺分割数))
        .and_then(|基点| 基点.checked_add(局所))
        .ok_or(アセットコンパイルエラー::散布の大域サンプル添字が範囲外 { チャンク成分 })?;
    i16::try_from(合計).map_err(|_| アセットコンパイルエラー::散布の大域サンプル添字が範囲外 { チャンク成分 })
}
