//! 散布が地表の面をどう読むかの2つの決め事。担当するのは、その面へ置いてよいかの判定と、置くときの傾け方である。
//!
//! 傾きを角度でなく「1メートル進むときに何メートル上がるか」で表し、比べるときも二乗のまま比べる。
//! 逆三角関数も平方根も通さないためであり、超越関数の近似は処理系ごとに違うから、境目の候補が
//! 別の機材では逆の判定になって散布の個体数が変わる。個体数が変われば実行時形式のバイト列が変わる。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「判断j」

use crate::error::アセットコンパイルエラー;
use crate::terrain::ground_surface::地表の面;

/// その種がどんな傾きの地面を好むか。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 傾きの好み {
    /// この傾きより急な面には置かない。斜面に立つと不自然な木に充てる。
    緩い面を好む { 傾きの上限: f32 },
    /// この傾きより緩い面には置かない。転がり落ちて溜まる岩に充てる。
    急な面を好む { 傾きの下限: f32 },
    /// 傾きを見ない。地面の形と関わりなく現れるものに充てる。
    傾きを見ない,
}

/// 個体を地表に対してどう据えるか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 地表への据え方 {
    /// 斜面でも天頂を向いて立てる。幹が重力の向きに伸びる木に充てる。
    垂直に立てる,
    /// 地表の法線へ倒す。面に乗って安定する岩に充てる。
    地表法線へ倒す,
}

impl 傾きの好み {
    pub(super) fn 検証する(self) -> Result<(), アセットコンパイルエラー> {
        let 閾値 = match self {
            Self::緩い面を好む { 傾きの上限 } => 傾きの上限,
            Self::急な面を好む { 傾きの下限 } => 傾きの下限,
            Self::傾きを見ない => return Ok(()),
        };
        if 閾値.is_finite() && 閾値 >= 0.0 {
            return Ok(());
        }
        Err(アセットコンパイルエラー::散布の傾きの閾値不正(閾値))
    }

    /// その面へ置いてよいか。比べるのは傾きの大きさの二乗どうしである。
    pub(super) fn 受け入れるか(self, 面: &地表の面) -> bool {
        match self {
            Self::緩い面を好む { 傾きの上限 } => 面.傾きの大きさの二乗() <= 傾きの上限 * 傾きの上限,
            Self::急な面を好む { 傾きの下限 } => 面.傾きの大きさの二乗() >= 傾きの下限 * 傾きの下限,
            Self::傾きを見ない => true,
        }
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::{傾きの好み, 地表への据え方};
    use crate::terrain::ground_surface::地表の面;

    fn 面(東の傾き: f32, 南の傾き: f32) -> 地表の面 {
        地表の面::生成する(0.0, 東の傾き, 南の傾き)
    }

    #[test]
    fn 緩い面を好む種は上限を超える斜面を拒む() {
        let 好み = 傾きの好み::緩い面を好む { 傾きの上限: 0.36 };
        assert!(好み.受け入れるか(&面(0.2, 0.2)), "傾き0.283の面を拒んだ");
        assert!(!好み.受け入れるか(&面(0.3, 0.3)), "傾き0.424の面を受け入れた");
    }

    #[test]
    fn 急な面を好む種は下限に届かない平地を拒む() {
        let 好み = 傾きの好み::急な面を好む { 傾きの下限: 0.14 };
        assert!(!好み.受け入れるか(&面(0.0, 0.0)), "平地を受け入れた");
        assert!(好み.受け入れるか(&面(0.2, 0.0)), "傾き0.2の面を拒んだ");
    }

    #[test]
    fn 傾きを見ない種はどの面も受け入れる() {
        assert!(傾きの好み::傾きを見ない.受け入れるか(&面(9.0, 9.0)));
    }

    #[test]
    fn 閾値が負や非有限なら拒む() {
        assert!(傾きの好み::緩い面を好む { 傾きの上限: -0.1 }.検証する().is_err());
        assert!(傾きの好み::急な面を好む { 傾きの下限: f32::NAN }.検証する().is_err());
    }

    #[test]
    fn 据え方は2つの枝を持つ() {
        assert_ne!(地表への据え方::垂直に立てる, 地表への据え方::地表法線へ倒す);
    }
}
