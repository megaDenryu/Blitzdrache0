//! 配置の種: 配置の混合関数へ入る、その世界の乱数の種から導いた値。担当するのは種の由来を混合へ足せる1つの値へ写すことだけである。
//!
//! 種を持たない世界で恒等(足しても混合が変わらない値)になることがこの型の不変条件である。恒等にしないと、
//! 手で書いた検証用の世界の配置が乱数の種と無関係に動き、既存の判定値が散布と無関係に変わる。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「判断j」

use crate::generation_ledger::種の由来;

/// 配置の混合へ足す値。排他的論理和で混ぜるため、恒等は0である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct 配置の種(u64);

impl 配置の種 {
    /// 種を持たない世界では恒等を返す。32ビットの種を上位へも届かせるのは、排他的論理和の相手が
    /// チャンク座標の永続化番号(上位32ビットが東、下位32ビットが南)であり、下位だけに足すと東の側へ1ビットも届かないためである。
    ///
    /// 注意: 上位へ種をそのまま写してはならない。上下が同じ値になると`密度場の種`が上下を畳んだときに
    /// 打ち消し合い、密度場から種が消えて森と草原の地図が世界の種に依らなくなる。上位は同じ種を混ぜた別の値にする。
    /// 混合が0を0へ写すため、種を持たない世界の恒等は保たれる。
    pub fn 種の由来から作る(由来: 種の由来) -> Self {
        match 由来 {
            種の由来::種から焼いた(種) => {
                let 下位 = u64::from(種.値());
                let 上位 = u64::from(crate::lattice_noise::整数を混ぜる(種.値()));
                Self(下位 | (上位 << 32))
            }
            種の由来::種を持たない => Self(0),
        }
    }

    pub(crate) fn 混合へ足す値(self) -> u64 {
        self.0
    }

    /// 密度場の格子雑音へ渡す種。雑音が32ビットの種を取るため、上位と下位を排他的論理和で畳んでから層のずらしを混ぜる。
    /// 層のずらしを取るのは、同じ世界の2種類の散布が同じ密度場を引くと、木の生える所に必ず岩も現れるためである。
    pub(crate) fn 密度場の種(self, 層のずらし: u32) -> u32 {
        let バイト列 = (self.0 ^ (self.0 >> 32)).to_le_bytes();
        u32::from_le_bytes([バイト列[0], バイト列[1], バイト列[2], バイト列[3]]) ^ 層のずらし
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::配置の種;
    use crate::generation_ledger::{マップ生成の乱数の種, 種の由来};

    #[test]
    fn 種を持たない世界では恒等である() {
        assert_eq!(配置の種::種の由来から作る(種の由来::種を持たない).混合へ足す値(), 0);
    }

    #[test]
    fn 種から焼いた世界では東の側にもビットが立つ() {
        let 値 = 配置の種::種の由来から作る(種の由来::種から焼いた(マップ生成の乱数の種::生成する(1))).混合へ足す値();
        assert_eq!(値 & 0xFFFF_FFFF, 1, "南の側へ種が届いていない");
        assert_ne!(値 >> 32, 0, "東の側へ種が届いていない");
        assert_ne!(値 >> 32, 値 & 0xFFFF_FFFF, "上下が同じ値では密度場の種を畳んだときに種が消える");
    }

    /// 密度場の種が層のずらしそのものになると、森と草原の地図が世界の種に依らなくなる。
    #[test]
    fn 種を変えると密度場の種が変わる() {
        let 層のずらし = 0x1D4F_A063;
        let 種から = |値| 配置の種::種の由来から作る(種の由来::種から焼いた(マップ生成の乱数の種::生成する(値))).密度場の種(層のずらし);
        let 一覧 = [種から(1), 種から(2), 種から(20260810), 種から(20260811), 種から(0xFFFF_FFFF)];
        for 種の値 in 一覧 {
            assert_ne!(種の値, 層のずらし, "密度場の種が層のずらしそのものになっており、世界の種が届いていない");
        }
        for (前, 後) in 一覧.iter().zip(一覧.iter().skip(1)) {
            assert_ne!(前, 後, "違う世界の種が同じ密度場の種になった");
        }
    }

    #[test]
    fn 種を持たない世界の密度場の種は層のずらしそのものである() {
        let 層のずらし = 0x8B31_C4A5;
        assert_eq!(配置の種::種の由来から作る(種の由来::種を持たない).密度場の種(層のずらし), 層のずらし);
    }

    #[test]
    fn 違う種は違う値になる() {
        let 一 = 配置の種::種の由来から作る(種の由来::種から焼いた(マップ生成の乱数の種::生成する(20260810)));
        let 二 = 配置の種::種の由来から作る(種の由来::種から焼いた(マップ生成の乱数の種::生成する(20260811)));
        assert_ne!(一, 二);
    }
}
