//! 部品で組んだ個体を地面へ散らす指定。担当するのは、散らす種1つを決める4つ(部品の一覧・組み立て規則・
//! 展開の種の起点・密度場の散布)を1つの値として持つことである。
//!
//! **`原型と置き方の指定`と別の型にするのは、返すものが違うためである。** あちらは1つの原型の配置列を返し、
//! こちらは部品ごとの配置の集約を返す。同じ`配置様式`の枝にすると、枝によって戻り値の型が変わる形になる。
//!
//! 散らす場所の決め方は原型を散らすときとまったく同じである。密度場と傾きと出現の判定で根の配置列を作り、
//! その1件ずつを組み立て規則で展開する。**走査の工程を共有するのは、同じ世界の木と岩が同じ格子の上に乗るためである。**
//! `種類の名前`を部品の名前で代用しないのは、1本が複数の部品になるため部品の名前では取り分を読めないからである。
//! `部品の安定id一覧`には、規則が指す部品がすべて在る必要がある。`種の起点`と同じ番号からは常に同じ姿が出る。
//! `密度場の散布`は原型を散らす様式と同じものを使う。
//! 参照: `_doc/設計/部品カタログと接合点.md`「段6: 散布の針葉樹を部品で組んだ木へ差し替える」

use blitz_assembly::{生成の種, 組み立て規則};

use crate::placed_instance_count::散らした種類の名前;
use blitz_engine::アセットID;

use super::scatter_specification::密度場の散布;

pub struct 部品で組む散布の指定 {
    pub 種類の名前: 散らした種類の名前, // 報告の内訳へ載せるこの種類の名前
    pub 部品の安定id一覧: Vec<アセットID>, // カタログへ載せる部品の安定ID
    pub 規則: 組み立て規則,
    pub 種の起点: 生成の種, // 個体1件ごとの種をここから番号で分ける
    pub 密度場の散布: 密度場の散布, // 根をどこへ置くかの決め方
}
