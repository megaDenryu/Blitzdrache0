//! 2つの範囲が値をどこへ写すかの検査。担当するのは、密度場の値と混合の値が範囲の両端と中ほどで
//! どの値になるかを課すことだけである。範囲の受け取れる値域の検査は`検証する`の側にある。
//!
//! この写しを検査するのは、散布の宣言が「草原には木を1本も置かない」ことをこの写しだけに頼っているためである。
//! 出現の割合の下限を0に置いても、密度場が最も低い所で割合が0にならなければ草原は作れない。

use super::{出現割合の範囲, 大きさの範囲};

/// 木の宣言が下限を0に置いて草原を作れる根拠がこの写しである。
#[test]
fn 出現の割合は密度場の両端で下限と上限になる() {
    let 範囲 = 出現割合の範囲 { 下限: 0.0, 上限: 0.9 };
    assert!(
        範囲.密度場の値から求める(-1.0).abs() <= f32::EPSILON,
        "密度場が最も低い所で下限にならなかった"
    );
    assert!(
        (範囲.密度場の値から求める(1.0) - 0.9).abs() <= f32::EPSILON,
        "密度場が最も高い所で上限にならなかった"
    );
    assert!(
        (範囲.密度場の値から求める(0.0) - 0.45).abs() <= f32::EPSILON,
        "密度場の中ほどで下限と上限の中点にならなかった"
    );
}

#[test]
fn 下限と上限が同じ範囲は密度場によらず同じ割合を返す() {
    let 範囲 = 出現割合の範囲 { 下限: 0.3, 上限: 0.3 };
    for 値 in [-1.0, -0.4, 0.0, 0.7, 1.0] {
        assert!(
            (範囲.密度場の値から求める(値) - 0.3).abs() <= f32::EPSILON,
            "密度場の値{値}で割合が動いた"
        );
    }
}

#[test]
fn 大きさは零以上一未満の値の両端で下限と上限へ寄る() {
    let 範囲 = 大きさの範囲 { 下限: 0.8, 上限: 1.6 };
    assert!(
        (範囲.零以上一未満の値から求める(0.0) - 0.8).abs() <= f32::EPSILON,
        "0で下限にならなかった"
    );
    assert!(
        (範囲.零以上一未満の値から求める(1.0) - 1.6).abs() <= f32::EPSILON,
        "1で上限にならなかった"
    );
}
