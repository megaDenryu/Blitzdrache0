//! 密度場で散らす様式が受け取る指定と、その検証。担当するのは、走査の細かさ・密度場の引き方・出現の割合・
//! 個体の大きさという4つの決め事を1つの値として持ち、受け取れない値を型付きエラーで拒むことである。
//!
//! 宣言の側が定数の表として書けるように、この型はフィールドを公開して`const`で組めるようにする。値の検証は
//! 配置列を作る入口の1箇所で行う。宣言1件ごとに検証つきの構築を通すと、表を`const`で書けなくなる。
//! 地表の傾きに対する好みと据え方は`ground_preference`が、値域を持つ2つの範囲は`scatter_ranges`が持つ。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「判断j」

use super::ground_preference::{傾きの好み, 地表への据え方};
use super::scatter_ranges::{出現割合の範囲, 大きさの範囲};
use crate::error::散布コンパイルエラー;

/// 密度場で散らす様式の指定。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 密度場の散布 {
    /// チャンクの1辺をいくつの走査の区画へ分けるか。置く候補の数はこの二乗であり、実際に置かれる数は出現の割合で減る。
    ///
    /// 注意: 型をu8にすることが上限の強制である。列数の二乗が配置の添字の型(u16)に収まる必要があり、
    /// u8の最大の255でも候補は65,025で収まる。したがって検証は0だけを拒めばよい。
    pub 走査の列数: u8,
    pub 密度場: 密度場の指定,
    pub 出現の割合: 出現割合の範囲,
    pub 傾きの好み: 傾きの好み,
    pub 大きさの範囲: 大きさの範囲,
    pub 据え方: 地表への据え方,
}

/// 密度場をどう引くか。升目の幅が森と草原の塊の大きさを決め、層のずらしが種ごとに違う塊を作る。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 密度場の指定 {
    /// 密度場の格子雑音の升目の幅を大域サンプル添字の数で表した値。高さの丘の層より広く取ると、塊が数チャンクにまたがる。
    pub 升目の標本数: i16,
    /// この種の密度場を他の種からずらす量。同じ世界の2種が同じ密度場を引くと、木の生える所に必ず岩も現れる。
    pub 層のずらし: u32,
}

impl 密度場の散布 {
    /// 受け取れない指定を1つ残らず拒む。散布は個体数を宣言せず密度から決めるため、指定の破れが
    /// 「1体も置かれない」または「候補の全部が置かれる」という絵の異常として遠くに現れる。
    pub(super) fn 検証する(self) -> Result<(), 散布コンパイルエラー> {
        if self.走査の列数 == 0 {
            return Err(散布コンパイルエラー::走査の列数不正(self.走査の列数));
        }
        if self.密度場.升目の標本数 <= 0 {
            return Err(散布コンパイルエラー::密度場の升目が正でない(
                self.密度場.升目の標本数,
            ));
        }
        self.出現の割合.検証する()?;
        self.大きさの範囲.検証する()?;
        self.傾きの好み.検証する()
    }
}
