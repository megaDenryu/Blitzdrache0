//! 原型1つ分の配置列をインスタンス群の描画対象へ組み立てる工程。受け取るのは地面の高さ格子と所有チャンクと
//! 描画対象番号と配置の混合の通し番号と原型と置き方の指定、返すのは描画対象と原型が参照したファイルの一覧である。
//!
//! 群の共有マテリアルは原型のglTFが宣言したものをそのまま使う。小物も木も岩も、色は作った本人がベースカラー係数で
//! 与えているため、コンパイラが選び直すと作者の宣言と絵が食い違う。植生の同居がマテリアルを選び直すのは、
//! 原型ソースが既定の白のままで地形と画素で見分けられないからであり、こちらにその事情は無い。
//!
//! 配置が0件のときに描画対象を作らず値なしを返すのは、密度場で散らす様式が個体数を密度から決めるためである。
//! インスタンス群は非空の配置列を要求するため、0件を空の群として焼く道は無い。

use std::path::PathBuf;

use blitz_engine::{チャンク座標, 描画対象データ};

use super::archetype_placement::原型と置き方の指定;
use super::mixing_serial::配置の混合の通し番号;
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子;
use crate::placed_instance_count::置いた個体の数;
use crate::scene_compiler::ソースアセットのコンパイル係;
use crate::vegetation::group_object;

/// 原型1つ分の群と、そこへ置いた個体の数と、その原型が読んだファイルの一覧。
pub(crate) struct 原型1つ分の群 {
    pub(crate) 描画対象: 描画対象データ,
    pub(crate) 置いた個体の数: 置いた個体の数,
    pub(crate) 参照ファイル一覧: Vec<PathBuf>,
}

impl ソースアセットのコンパイル係<'_> {
    pub(crate) fn 原型1つ分の群の描画対象を作る(
        &self,
        格子: &高さ格子,
        所有チャンク: チャンク座標,
        描画対象番号: u64,
        通し番号: 配置の混合の通し番号,
        指定: &原型と置き方の指定,
    ) -> Result<Option<原型1つ分の群>, アセットコンパイルエラー> {
        let 配置一覧 = super::配置列を作る(格子, 所有チャンク, 通し番号, self.配置の種を貸す(), 指定.配置様式)?;
        if 配置一覧.is_empty() {
            return Ok(None);
        }
        let 原型ソース = self.原型ソースを読み込む(&指定.原型id)?;
        let 群 = group_object::群の描画対象を作る(描画対象番号, 所有チャンク, 原型ソース.段一覧, 原型ソース.材質集合, 配置一覧)?;
        Ok(Some(原型1つ分の群 {
            描画対象: 群.描画対象,
            置いた個体の数: 群.置いた個体の数,
            参照ファイル一覧: 原型ソース.参照ファイル一覧,
        }))
    }
}
