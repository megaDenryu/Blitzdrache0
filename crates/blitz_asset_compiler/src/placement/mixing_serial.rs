//! 配置の混合の通し番号: 配置の混合関数へ入れる、同じシーンの中で群どうしの並びを分けるための番号。
//!
//! 描画対象番号と別の型で持つのは、2つを決めてよい根拠が違うためである。描画対象番号はシーンの中で一意で
//! ありさえすればよく、地面と固定物と群を通して1つずつ進む。混合の通し番号は配置そのものを決めるため、
//! 群より前に何を何個据えたかで動いてはならない。どちらもu64であるから、同じ型で持つと取り違えても呼び出しが
//! 通り、目印を1つ据えただけでその先の散布の配置が丸ごと入れ替わる。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub(crate) struct 配置の混合の通し番号(u64);

impl 配置の混合の通し番号 {
    /// 散布の一覧の先頭。散布は一覧の中での順番だけで通し番号を決めるため、固定物を何個据えても先頭はこの値である。
    pub(crate) fn 散布の一覧の先頭() -> Self {
        Self(0)
    }

    /// 描画対象番号をそのまま通し番号にする。見本の集落と目視見本は群より前に置く物の数が宣言で固定されており、
    /// 通し番号の決め方を変えると既に焼いた絵の判定値が動く。
    pub(crate) fn 描画対象番号から生成する(描画対象番号: u64) -> Self {
        Self(描画対象番号)
    }

    /// 一覧の次の1件へ進める。
    pub(crate) fn 次の1件へ進める(self) -> Self {
        Self(self.0 + 1)
    }

    pub(crate) fn 混合へ入れる値(self) -> u64 {
        self.0
    }
}
