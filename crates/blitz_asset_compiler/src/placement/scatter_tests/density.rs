//! 出現の割合が実際に置く数を決めていることの検査。割合の両端を課すのは、密度場の写しの符号を
//! 取り違えると森と草原が入れ替わり、絵を見るまで気づけないためである。

use blitz_engine::チャンク座標;

use super::super::ground_preference::{傾きの好み, 地表への据え方};
use super::super::scatter_ranges::出現割合の範囲;
use super::fixture::{必ず置く, 指定, 散らす, 種から作る, 走査の列数};

#[test]
fn 出現の割合が零なら1体も置かれない() {
    let 様式 = 指定(
        出現割合の範囲 { 下限: 0.0, 上限: 0.0 },
        傾きの好み::傾きを見ない,
        地表への据え方::垂直に立てる,
    );
    assert!(散らす(チャンク座標::生成する(0, 0), 種から作る(1), 様式, 0.0).is_empty());
}

#[test]
fn 出現の割合が一なら走査の区画の全部に置かれる() {
    let 様式 = 指定(必ず置く(), 傾きの好み::傾きを見ない, 地表への据え方::垂直に立てる);
    let 配置一覧 = 散らす(チャンク座標::生成する(0, 0), 種から作る(1), 様式, 0.0);
    assert_eq!(配置一覧.len(), usize::from(走査の列数) * usize::from(走査の列数));
}
