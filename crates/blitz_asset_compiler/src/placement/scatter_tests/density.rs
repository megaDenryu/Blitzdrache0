//! 出現の割合が実際に置く数を決めていることの検査。割合の両端を課すのは、密度場の写しの符号を
//! 取り違えると森と草原が入れ替わり、絵を見るまで気づけないためである。

use blitz_engine::チャンク座標;

use super::super::ground_preference::{傾きの好み, 地表への据え方};
use super::super::scatter_ranges::出現割合の範囲;
use super::super::seed::配置の種;
use super::fixture::{升目の標本数, 層のずらし, 必ず置く, 指定, 散らす, 検査用辺分割数, 種から作る, 走査の列数};
use crate::lattice_noise::格子雑音の値;

#[test]
fn 出現の割合が零なら1体も置かれない() {
    let 様式 = 指定(
        出現割合の範囲 { 下限: 0.0, 上限: 0.0 },
        傾きの好み::傾きを見ない,
        地表への据え方::垂直に立てる,
    );
    assert!(散らす(チャンク座標::生成する(0, 0), 種から作る(1), 様式, 0.0).is_empty());
}

#[test]
fn 出現の割合が一なら走査の区画の全部に置かれる() {
    let 様式 = 指定(必ず置く(), 傾きの好み::傾きを見ない, 地表への据え方::垂直に立てる);
    let 配置一覧 = 散らす(チャンク座標::生成する(0, 0), 種から作る(1), 様式, 0.0);
    assert_eq!(配置一覧.len(), usize::from(走査の列数) * usize::from(走査の列数));
}

/// 密度場が世界の種を受け取っていないと、森と草原の地図がどの世界でも同じ場所に出る。
/// 絵を見ても「そういう地形なのだ」としか読めないため、ここで数として課す。
#[test]
fn 種を変えると密度場の値が変わる() {
    let 一 = チャンクの原点の密度場の値(種から作る(1), 0);
    let 二 = チャンクの原点の密度場の値(種から作る(2), 0);
    let 三 = チャンクの原点の密度場の値(種から作る(20260810), 0);
    assert_ne!(一, 二, "種1と種2で密度場の値が同じである");
    assert_ne!(二, 三, "種2と種20260810で密度場の値が同じである");
    assert_ne!(一, 三, "種1と種20260810で密度場の値が同じである");
}

/// 密度場が実際に個体数を上下させていることを課す。出現の割合を0から1へ広げ、傾きを見ないことで、
/// 個体数を決める要因を密度場だけに絞る。
#[test]
fn 密度場の低い区画の個体数は高い区画より少ない() {
    let 種 = 種から作る(20260810);
    let 様式 = 指定(
        出現割合の範囲 { 下限: 0.0, 上限: 1.0 },
        傾きの好み::傾きを見ない,
        地表への据え方::垂直に立てる,
    );
    let 一覧: Vec<(f32, usize)> = (0..40)
        .map(|東| {
            let 個体数 = 散らす(チャンク座標::生成する(東, 0), 種, 様式, 0.0).len();
            (チャンクの原点の密度場の値(種, 東), 個体数)
        })
        .collect();
    let 最も高い = 一覧.iter().max_by(|左, 右| 左.0.total_cmp(&右.0)).unwrap();
    let 最も低い = 一覧.iter().min_by(|左, 右| 左.0.total_cmp(&右.0)).unwrap();
    assert!(最も高い.0 > 最も低い.0, "40区画の密度場の値が1つも動いていない");
    assert!(
        最も高い.1 > 最も低い.1,
        "密度場が最も高い区画({}体)が最も低い区画({}体)より多くない",
        最も高い.1,
        最も低い.1
    );
}

/// そのチャンクの原点にあたる大域サンプル添字での密度場の値。原点の局所の格子添字は0であるため、
/// 大域サンプル添字はチャンク成分と辺分割数の積そのものになる。
fn チャンクの原点の密度場の値(種: 配置の種, 東のチャンク成分: i32) -> f32 {
    let 添字 = i16::try_from(東のチャンク成分 * i32::from(検査用辺分割数)).unwrap();
    格子雑音の値(種.密度場の種(層のずらし), 添字, 0, 升目の標本数)
}
