//! 個体がチャンクの内側に収まることと、天頂成分が最詳細段の面の高さと一致することの検査。
//! チャンクの外へ出た個体は隣のチャンクの地面へめり込み、面から離れた個体は宙に浮くか埋まる。

use blitz_engine::チャンク座標;

use super::super::ground_preference::{傾きの好み, 地表への据え方};
use super::super::配置列を作る;
use super::fixture::{
    一定の傾きの格子, 必ず置く, 指定, 散らす, 検査用の通し番号, 検査用一辺メートル, 種から作る
};
use crate::terrain::ground_height;

#[test]
fn 個体はチャンクの内側に収まる() {
    let 様式 = 指定(必ず置く(), 傾きの好み::傾きを見ない, 地表への据え方::垂直に立てる);
    for 配置 in 散らす(チャンク座標::生成する(-4, 5), 種から作る(20260810), 様式, 0.2) {
        let 位置 = 配置.平行移動();
        assert!((0.0..検査用一辺メートル).contains(&位置[0]), "東がチャンクの外である: {位置:?}");
        assert!((0.0..検査用一辺メートル).contains(&位置[2]), "南がチャンクの外である: {位置:?}");
    }
}

#[test]
fn 個体の天頂成分は最詳細段の面の高さと一致する() {
    for 据え方 in [地表への据え方::垂直に立てる, 地表への据え方::地表法線へ倒す] {
        let 様式 = 指定(必ず置く(), 傾きの好み::傾きを見ない, 据え方);
        let チャンク = チャンク座標::生成する(2, 2);
        let 格子 = 一定の傾きの格子(チャンク, 0.35);
        for 配置 in 配置列を作る(&格子, チャンク, 検査用の通し番号(), 種から作る(20260810), 様式).unwrap() {
            let 位置 = 配置.平行移動();
            let 面の高さ = ground_height::地表高さを求める(&格子, 位置[0], 位置[2]).unwrap();
            assert!((位置[1] - 面の高さ).abs() < 1e-4, "個体が面から離れている: {位置:?}と{面の高さ}");
        }
    }
}
