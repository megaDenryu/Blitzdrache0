//! 同じ入力から同じ配置列が出ること、違う入力からは違う配置列が出ることの検査。
//! 決定性が破れると、同じ種から焼いた2つの生成物が食い違い、増分の鍵が意味を失う。

use blitz_engine::チャンク座標;

use super::super::ground_preference::{傾きの好み, 地表への据え方};
use super::fixture::{必ず置く, 指定, 散らす, 種から作る};

#[test]
fn 同じ種と同じ座標からは同じ配置列が出る() {
    let 様式 = 指定(必ず置く(), 傾きの好み::傾きを見ない, 地表への据え方::垂直に立てる);
    let 一度目 = 散らす(チャンク座標::生成する(3, -2), 種から作る(20260810), 様式, 0.1);
    let 二度目 = 散らす(チャンク座標::生成する(3, -2), 種から作る(20260810), 様式, 0.1);
    assert_eq!(一度目.len(), 二度目.len());
    for (左, 右) in 一度目.iter().zip(二度目.iter()) {
        assert_eq!(左.平行移動(), 右.平行移動(), "同じ入力から違う位置が出た");
        assert_eq!(左.回転(), 右.回転(), "同じ入力から違う回転が出た");
    }
}

#[test]
fn 隣り合うチャンクは違う並びになる() {
    let 様式 = 指定(必ず置く(), 傾きの好み::傾きを見ない, 地表への据え方::垂直に立てる);
    let 種 = 種から作る(20260810);
    let 左 = 散らす(チャンク座標::生成する(0, 0), 種, 様式, 0.0);
    let 右 = 散らす(チャンク座標::生成する(1, 0), 種, 様式, 0.0);
    assert_ne!(左[0].平行移動(), 右[0].平行移動(), "隣のチャンクが同じ並びになった");
}

#[test]
fn 種を変えると並びが変わる() {
    let 様式 = 指定(必ず置く(), 傾きの好み::傾きを見ない, 地表への据え方::垂直に立てる);
    let チャンク = チャンク座標::生成する(0, 0);
    let 一 = 散らす(チャンク, 種から作る(20260810), 様式, 0.0);
    let 二 = 散らす(チャンク, 種から作る(20260811), 様式, 0.0);
    assert_ne!(一[0].平行移動(), 二[0].平行移動(), "種を変えても同じ並びになった");
}
