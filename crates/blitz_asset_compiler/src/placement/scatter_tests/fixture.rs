//! 散布の検査が共通して使う材料。高さ格子の作り方・散布の指定の組み立て・種の作り方をここが所有する。
//!
//! 高さ格子を検査の側で組み立てるのは、この様式が読むのが高さ格子と種だけであり、世界の宣言を通さずに
//! 全部の枝を動かせるためである。傾きを引数で決めるため、傾きの好みの両側を1つの作り方で試せる。

use blitz_engine::{チャンク座標, 個体配置};

use super::super::ground_preference::{傾きの好み, 地表への据え方};
use super::super::scatter_ranges::{出現割合の範囲, 大きさの範囲};
use super::super::scatter_specification::{密度場の指定, 密度場の散布};
use super::super::seed::配置の種;
use super::super::{配置列を作る, 配置様式};
use crate::generation_ledger::{マップ生成の乱数の種, 種の由来};
use crate::height_grid::{高さ格子, 高さ格子を切り出す, 高さ格子諸元};

pub(super) const 検査用辺分割数: u16 = 64;
pub(super) const 検査用一辺メートル: f32 = 100.0;
pub(super) const 走査の列数: u8 = 8;

pub(super) fn 諸元() -> 高さ格子諸元 {
    高さ格子諸元::生成する(検査用辺分割数, 1, 検査用一辺メートル).unwrap()
}

/// 東へ一定の傾きで上がる斜面。傾きを引数で決めるため、傾きの好みの両側を1つの作り方で試せる。
pub(super) fn 一定の傾きの格子(チャンク: チャンク座標, 東の傾き: f32) -> 高さ格子 {
    let 刻み = 諸元().刻みメートル();
    高さ格子を切り出す(諸元(), チャンク, |添字x, _| f32::from(添字x) * 刻み * 東の傾き).unwrap()
}

pub(super) fn 指定(出現の割合: 出現割合の範囲, 傾きの好み: 傾きの好み, 据え方: 地表への据え方) -> 配置様式 {
    配置様式::密度場で散らす(密度場の散布 {
        走査の列数,
        密度場: 密度場の指定 {
            升目の標本数: 240,
            層のずらし: 0x51ED_2701,
        },
        出現の割合,
        傾きの好み,
        大きさの範囲: 大きさの範囲 { 下限: 0.8, 上限: 1.4 },
        据え方,
    })
}

pub(super) fn 必ず置く() -> 出現割合の範囲 {
    出現割合の範囲 { 下限: 1.0, 上限: 1.0 }
}

pub(super) fn 散らす(チャンク: チャンク座標, 種: 配置の種, 様式: 配置様式, 東の傾き: f32) -> Vec<個体配置> {
    配置列を作る(&一定の傾きの格子(チャンク, 東の傾き), チャンク, 3, 種, 様式).unwrap()
}

pub(super) fn 種から作る(値: u32) -> 配置の種 {
    配置の種::種の由来から作る(種の由来::種から焼いた(マップ生成の乱数の種::生成する(値)))
}
