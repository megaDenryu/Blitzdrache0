//! 地表の傾きの好みが置く置かないを決めていることの検査。両側の好みについて、拒む面と受け入れる面を
//! 1つずつ課す。受け入れる側を課さないと、常に0件を返す実装が検査を通る。

use blitz_engine::チャンク座標;

use super::super::ground_preference::{傾きの好み, 地表への据え方};
use super::fixture::{必ず置く, 指定, 散らす, 種から作る};

#[test]
fn 緩い面を好む種は急斜面へ1体も置かない() {
    let 様式 = 指定(必ず置く(), 傾きの好み::緩い面を好む { 傾きの上限: 0.36 }, 地表への据え方::垂直に立てる);
    let チャンク = チャンク座標::生成する(0, 0);
    assert!(散らす(チャンク, 種から作る(1), 様式, 0.9).is_empty(), "傾き0.9の斜面へ置いた");
    assert!(
        !散らす(チャンク, 種から作る(1), 様式, 0.1).is_empty(),
        "傾き0.1の緩い面へ1体も置かなかった"
    );
}

#[test]
fn 急な面を好む種は平地へ1体も置かない() {
    let 様式 = 指定(必ず置く(), 傾きの好み::急な面を好む { 傾きの下限: 0.5 }, 地表への据え方::垂直に立てる);
    let チャンク = チャンク座標::生成する(0, 0);
    assert!(散らす(チャンク, 種から作る(1), 様式, 0.0).is_empty(), "平地へ置いた");
    assert!(!散らす(チャンク, 種から作る(1), 様式, 0.8).is_empty(), "傾き0.8の斜面へ1体も置かなかった");
}
