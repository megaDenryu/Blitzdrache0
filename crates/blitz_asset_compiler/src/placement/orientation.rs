//! 個体の回転を作る工程。受け取るのは天頂まわりの角度と、倒すなら地表の面、返すのは単位クォータニオンである。
//!
//! 天頂まわりの回転に三角関数を使うのは既存の配置と同じである。倒す側は三角関数を使わず、
//! 天頂から法線への回転を半分のベクトルから直に組む。逆三角関数で角度へ戻してから正弦余弦で戻すと、
//! 近似の誤差が2回入るためである。
//!
//! ここが回転の作り方の唯一の置き場である。据え方の枝ごとに呼び出し側で組むと、
//! 積の順序を取り違えた回転が種ごとに現れる。

use crate::terrain::ground_surface::地表の面;

/// 天頂軸まわりの回転。地面に立つものはこれだけで向きが決まる。
pub(super) fn 天頂まわりの回転を作る(角度: f32) -> [f32; 4] {
    let 半角 = 角度 * 0.5;
    [0.0, 半角.sin(), 0.0, 半角.cos()]
}

/// 天頂まわりに回してから地表の法線へ倒した回転。天頂を法線へ写す回転を左から掛けるため、
/// 天頂まわりの回し量は面の上での向きとして残る。
pub(super) fn 地表法線へ倒した回転を作る(面: &地表の面, 天頂まわりの角度: f32) -> [f32; 4] {
    掛ける(天頂を法線へ写す回転(面), 天頂まわりの回転を作る(天頂まわりの角度))
}

/// 天頂(0,1,0)を法線へ写す最短の回転。半分のベクトルを使う形であり、外積が回転軸に、
/// 1と内積の和が実部になる。法線が真下を向くと長さが0になるが、地表の法線は天頂成分が常に正であるため起きない。
fn 天頂を法線へ写す回転(面: &地表の面) -> [f32; 4] {
    let 法線 = 面.正した法線();
    let 正す前 = [法線[2], 0.0, -法線[0], 1.0 + 法線[1]];
    正す(正す前)
}

/// クォータニオンの積。左の回転を後から掛ける順序であり、右が先に効く。
fn 掛ける(左: [f32; 4], 右: [f32; 4]) -> [f32; 4] {
    let [左x, 左y, 左z, 左w] = 左;
    let [右x, 右y, 右z, 右w] = 右;
    正す([
        左w * 右x + 左x * 右w + 左y * 右z - 左z * 右y,
        左w * 右y - 左x * 右z + 左y * 右w + 左z * 右x,
        左w * 右z + 左x * 右y - 左y * 右x + 左z * 右w,
        左w * 右w - 左x * 右x - 左y * 右y - 左z * 右z,
    ])
}

/// 長さを1に正す。個体配置は単位クォータニオンだけを受け取るため、積を重ねた丸めをここで戻す。
fn 正す(値: [f32; 4]) -> [f32; 4] {
    let 長さ = (値[0] * 値[0] + 値[1] * 値[1] + 値[2] * 値[2] + 値[3] * 値[3]).sqrt();
    [値[0] / 長さ, 値[1] / 長さ, 値[2] / 長さ, 値[3] / 長さ]
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::{地表法線へ倒した回転を作る, 天頂まわりの回転を作る};
    use crate::terrain::ground_surface::地表の面;

    /// クォータニオンでベクトルを回す。検査の側が回転の意味を独立に持つため、実装の写しにならない。
    fn 回す(回転: [f32; 4], 元: [f32; 3]) -> [f32; 3] {
        let [x, y, z, w] = 回転;
        let 外積 = [y * 元[2] - z * 元[1], z * 元[0] - x * 元[2], x * 元[1] - y * 元[0]];
        let 足す = [外積[0] + w * 元[0], 外積[1] + w * 元[1], 外積[2] + w * 元[2]];
        let 二重外積 = [y * 足す[2] - z * 足す[1], z * 足す[0] - x * 足す[2], x * 足す[1] - y * 足す[0]];
        [元[0] + 2.0 * 二重外積[0], 元[1] + 2.0 * 二重外積[1], 元[2] + 2.0 * 二重外積[2]]
    }

    #[test]
    fn 平らな面では倒す回転が天頂まわりの回転と同じ向きを作る() {
        let 面 = 地表の面::生成する(0.0, 0.0, 0.0);
        let 倒した = 回す(地表法線へ倒した回転を作る(&面, 0.7), [1.0, 0.0, 0.0]);
        let 立てた = 回す(天頂まわりの回転を作る(0.7), [1.0, 0.0, 0.0]);
        for 軸 in 0..3 {
            assert!((倒した[軸] - 立てた[軸]).abs() < 1e-5, "軸{軸}が食い違う: {倒した:?}と{立てた:?}");
        }
    }

    #[test]
    fn 倒す回転は個体の天頂を地表の法線へ写す() {
        let 面 = 地表の面::生成する(0.0, 0.4, -0.25);
        let 写した = 回す(地表法線へ倒した回転を作る(&面, 1.3), [0.0, 1.0, 0.0]);
        let 法線 = 面.正した法線();
        for 軸 in 0..3 {
            assert!((写した[軸] - 法線[軸]).abs() < 1e-5, "軸{軸}が法線と食い違う: {写した:?}と{法線:?}");
        }
    }

    #[test]
    fn 作る回転はどちらも単位の長さである() {
        let 面 = 地表の面::生成する(0.0, 1.7, 0.9);
        for 回転 in [天頂まわりの回転を作る(2.4), 地表法線へ倒した回転を作る(&面, 2.4)] {
            let 二乗和 = 回転.iter().map(|値| 値 * 値).sum::<f32>();
            assert!((二乗和 - 1.0).abs() < 1e-5, "長さが1でない: {回転:?}");
        }
    }
}
