//! 採番の検査。担当するのは、固定物の据え付けの数を変えても散布の配置が動かないことと、描画対象番号のほうは
//! 据え付けの数だけ後ろへずれて重複しないことの2つを反証することである。
//!
//! 番号どうしの比べで止めず配置列そのものを突き合わせるのは、通し番号が配置の混合の種へ入るためである。
//! 番号の作り方だけを見ると、種へ渡す先を取り違えた変更を見逃す。

#![allow(clippy::unwrap_used)]

use blitz_engine::{チャンク座標, 個体配置};

use super::固定物を据えたシーンの採番;
use crate::generation_ledger::種の由来;
use crate::height_grid::{高さ格子, 高さ格子を切り出す, 高さ格子諸元};
use crate::placement::{
    傾きの好み, 出現割合の範囲, 地表への据え方, 大きさの範囲, 密度場の指定, 密度場の散布, 配置の種, 配置列を作る, 配置様式
};

const 地面の描画対象番号: u64 = 0;
const 検査するチャンク: (i32, i32) = (2, -1);
const 散布の種類数: usize = 3;

fn 平らな格子(チャンク: チャンク座標) -> 高さ格子 {
    高さ格子を切り出す(高さ格子諸元::生成する(64, 1, 100.0).unwrap(), チャンク, |_, _| 0.0).unwrap()
}

/// 密度場で必ず置く様式。傾きを見ないため、平らな格子でも走査した升目の全部に個体が立つ。
fn 必ず置く様式() -> 配置様式 {
    配置様式::密度場で散らす(密度場の散布 {
        走査の列数: 8,
        密度場: 密度場の指定 {
            升目の標本数: 240,
            層のずらし: 0x51ED_2701,
        },
        出現の割合: 出現割合の範囲 { 下限: 1.0, 上限: 1.0 },
        傾きの好み: 傾きの好み::傾きを見ない,
        大きさの範囲: 大きさの範囲 { 下限: 0.8, 上限: 1.4 },
        据え方: 地表への据え方::垂直に立てる,
    })
}

/// 固定物を指定の数だけ据えたシーンで、散布の各原型がどの配置列とどの描画対象番号を得るかを再現する。
fn 据え付けの数を決めて散布を再現する(据え付けの数: usize) -> Vec<(u64, Vec<個体配置>)> {
    let チャンク = チャンク座標::生成する(検査するチャンク.0, 検査するチャンク.1);
    let 格子 = 平らな格子(チャンク);
    let 種 = 配置の種::種の由来から作る(種の由来::種を持たない);
    let mut 採番 = 固定物を据えたシーンの採番::地面の描画対象番号の次から始める(地面の描画対象番号);
    for _ in 0..据え付けの数 {
        採番.描画対象番号を1つ配る();
    }
    (0..散布の種類数)
        .map(|_| {
            let 番号 = 採番.散布1件へ番号を配る();
            let 配置列 = 配置列を作る(&格子, チャンク, 番号.配置の混合の通し番号, 種, 必ず置く様式()).unwrap();
            (番号.描画対象番号, 配置列)
        })
        .collect()
}

#[test]
fn 固定物の据え付けの数を変えても散布の配置列は変わらない() {
    let 据え付け無し = 据え付けの数を決めて散布を再現する(0);
    let 据え付け5件 = 据え付けの数を決めて散布を再現する(5);
    for ((_, 無しの配置列), (_, 五件の配置列)) in 据え付け無し.iter().zip(据え付け5件.iter()) {
        assert_eq!(無しの配置列.len(), 五件の配置列.len(), "据え付けの数で散布の個体数が変わった");
        assert!(!無しの配置列.is_empty(), "検査が1体も置かない条件になっている");
        for (無しの配置, 五件の配置) in 無しの配置列.iter().zip(五件の配置列.iter()) {
            assert_eq!(無しの配置.平行移動(), 五件の配置.平行移動(), "据え付けの数で散布の位置が変わった");
            assert_eq!(無しの配置.回転(), 五件の配置.回転(), "据え付けの数で散布の向きが変わった");
        }
    }
}

#[test]
fn 散布の描画対象番号は据え付けの数だけ後ろへずれる() {
    let 据え付け無し = 据え付けの数を決めて散布を再現する(0);
    let 据え付け5件 = 据え付けの数を決めて散布を再現する(5);
    for ((無しの番号, _), (五件の番号, _)) in 据え付け無し.iter().zip(据え付け5件.iter()) {
        assert_eq!(無しの番号 + 5, *五件の番号, "描画対象番号が固定物のぶんだけ空いていない");
    }
}
