//! 固定物を据えたシーンの採番。担当するのは、地面の次から配る描画対象番号と、散布が配置の混合へ渡す通し番号を
//! 別々に進めることである。受け取るのは地面が取った描画対象番号、返すのは固定物1つぶんの描画対象番号と、
//! 散布1件ぶんの2つの番号である。
//!
//! 2つを別々に進めるのは、描画対象番号がシーンの中で一意でありさえすればよいのに対し、混合の通し番号が配置そのものを
//! 決めるためである。1つの番号を両方に使うと、目印を1つ据えたチャンクではその先の散布の配置が丸ごと入れ替わる。
//! 据え付けの数と散布の分布は無関係でなければならない。
//!
//! 1体も置かなかった散布でも両方の番号を進める。置いた数で番号を詰めると、ある原型の配置が
//! 「自分より前の原型が何体置いたか」で変わる。

#[cfg(test)]
mod numbering_tests;

use crate::placement::配置の混合の通し番号;

/// 散布1件へ配る2つの番号。
pub(super) struct 散布1件へ配る番号 {
    pub(super) 描画対象番号: u64,
    pub(super) 配置の混合の通し番号: 配置の混合の通し番号,
}

pub(super) struct 固定物を据えたシーンの採番 {
    次の描画対象番号: u64,
    次の散布の通し番号: 配置の混合の通し番号,
}

impl 固定物を据えたシーンの採番 {
    pub(super) fn 地面の描画対象番号の次から始める(地面の描画対象番号: u64) -> Self {
        Self {
            次の描画対象番号: 地面の描画対象番号 + 1,
            次の散布の通し番号: 配置の混合の通し番号::散布の一覧の先頭(),
        }
    }

    pub(super) fn 固定物1つへ描画対象番号を配る(&mut self) -> u64 {
        let 番号 = self.次の描画対象番号;
        self.次の描画対象番号 = 番号 + 1;
        番号
    }

    pub(super) fn 散布1件へ番号を配る(&mut self) -> 散布1件へ配る番号 {
        let 配った番号 = 散布1件へ配る番号 {
            描画対象番号: self.次の描画対象番号,
            配置の混合の通し番号: self.次の散布の通し番号,
        };
        self.次の描画対象番号 = 配った番号.描画対象番号 + 1;
        self.次の散布の通し番号 = 配った番号.配置の混合の通し番号.次の1件へ進める();
        配った番号
    }
}
