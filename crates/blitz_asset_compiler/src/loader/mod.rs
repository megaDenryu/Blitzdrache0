use crate::error::アセットコンパイルエラー;

const 単一アセット描画対象番号: u64 = 0;

impl ソースアセットのコンパイル係<'_> {
    /// カタログでidを参照し、glTF(.gltf/.glb)の最初のメッシュを読み込む。
    /// 所有チャンクはソースが持たない情報のため呼出し側が決める(ストリーミング対象でないアセットは原点チャンク)。
    /// メッシュ内の全プリミティブを頂点ずらし量付きで連結し(判断37)、プリミティブごとのインデックス区間と材質スロットIDを残す。
    /// 材質集合は対象メッシュのプリミティブが参照するマテリアルだけを、出現順のスロット番号で持つ。
    /// 複数メッシュ・階層はM3スコープ外(参照: 開発スレッド「判断22」)。
    /// スキンを持つノードに紐づくメッシュなら、スキンとアニメーション一覧も読み込む(判断42)。
    pub fn ソースシーンを読み込む(
        &self,
        id: &アセットID,
        所有チャンク: チャンク座標,
    ) -> Result<シーンデータ, アセットコンパイルエラー> {
        self.寸法を合わせる倍率を与えてソースシーンを読み込む(id, 所有チャンク, 寸法を合わせる一様倍率::等倍())
    }

    /// 実寸のメートルで書かれていないソースを、倍率で実寸へ合わせながら読み込む。倍率はローカルからワールドへの変換に載るため、
    /// スキニングで動かした頂点にも、動く個体として平行移動と天頂軸まわりの向きを差し替えた個体にも同じように効く。
    pub fn 寸法を合わせる倍率を与えてソースシーンを読み込む(
        &self,
        id: &アセットID,
        所有チャンク: チャンク座標,
        倍率: 寸法を合わせる一様倍率,
    ) -> Result<シーンデータ, アセットコンパイルエラー> {
        let パス = self.安定idが指すソースのパスを参照する(id)?;

        let 開いた文書 = document::文書を開く(パス)?;
        let 対象メッシュ = 開いた文書.document.meshes().next().ok_or(アセットコンパイルエラー::メッシュなし)?;
        if 対象メッシュ.primitives().next().is_none() {
            return Err(アセットコンパイルエラー::プリミティブなし);
        }

        let スキン読込結果 = skin::スキンを取り出す(&開いた文書, 対象メッシュ.index())?;

        let 材質スロット = material_slots::解決する(&開いた文書, std::iter::once(対象メッシュ.clone()), self.テクスチャの格納方針())?;
        let メッシュ実体 = mesh::メッシュデータを取り出す(
            &開いた文書,
            &対象メッシュ,
            スキン読込結果.as_ref().map(|(_, 関節解決)| 関節解決),
            &材質スロット.語彙,
        )?;

        let アニメーション一覧 = match &スキン読込結果 {
            Some((データ, 関節解決)) => {
                animation::アニメーション一覧を取り出す(&開いた文書, 関節解決, データ.ジョイント一覧.len())?
            }
            None => Vec::new(),
        };

        let mut 参照ファイル一覧 = 開いた文書.参照ファイル一覧;
        参照ファイル一覧.extend(材質スロット.参照ファイル一覧);

        let 描画対象 = 描画対象データ::生成する(
            描画対象ID::生成する(単一アセット描画対象番号),
            所有チャンク,
            倍率.変換へ写す(),
            描画形状::通常メッシュ(メッシュ実体),
            材質スロット.材質集合,
        );

        Ok(シーンデータ::生成する(
            描画対象,
            Vec::new(),
            参照ファイル一覧,
            スキン読込結果.map(|(データ, _)| データ),
            アニメーション一覧,
        ))
    }
}
