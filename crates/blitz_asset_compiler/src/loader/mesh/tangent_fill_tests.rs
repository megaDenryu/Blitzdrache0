//! 接線構成(判断46)の単体テスト: 法線との直交性・単位長・authored値の保持。

use super::tangent_fill::接線を確定する;

fn 内積(a: [f32; 3], b: [f32; 3]) -> f32 {
    a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
}

fn 直交かつ単位長であることを確認する(法線: [f32; 3], 接線: [f32; 4]) {
    let 接線ベクトル = [接線[0], 接線[1], 接線[2]];
    assert!((内積(接線ベクトル, 接線ベクトル) - 1.0).abs() < 1e-5, "接線は単位長のはず: {接線ベクトル:?}");
    assert!(内積(法線, 接線ベクトル).abs() < 1e-5, "接線は法線と直交するはず: 法線={法線:?} 接線={接線ベクトル:?}");
    assert_eq!(接線[3], 1.0);
}

#[test]
fn x軸から離れた法線は直交単位接線を生成する() {
    let 法線一覧 = [[0.0, 0.0, 1.0]];
    let 結果 = 接線を確定する(&法線一覧, vec![None]);
    直交かつ単位長であることを確認する(法線一覧[0], 結果[0]);
}

#[test]
fn x軸にほぼ平行な法線でも退化せず直交単位接線を生成する() {
    let 法線一覧 = [[1.0, 0.0, 0.0]];
    let 結果 = 接線を確定する(&法線一覧, vec![None]);
    直交かつ単位長であることを確認する(法線一覧[0], 結果[0]);
}

#[test]
fn authored接線は保持される() {
    let 法線一覧 = [[0.0, 0.0, 1.0]];
    let 結果 = 接線を確定する(&法線一覧, vec![Some([1.0, 0.0, 0.0, -1.0])]);
    assert_eq!(結果[0], [1.0, 0.0, 0.0, -1.0]);
}
