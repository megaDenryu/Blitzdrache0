use super::material_slots::材質スロット語彙;
use super::skin::関節解決;

/// 全プリミティブの頂点・インデックスを、後続プリミティブのインデックスへ先行プリミティブの頂点数ぶんのずらし量を
/// 加算しながら連結する。同じ走査でプリミティブごとのインデックス区間と材質スロットIDを記録し、材質の境界を残す。
/// 頂点基準を常に0にするのは、ずらし量をインデックスの値へ焼き込んだ後だからである。
/// `関節解決`が`Some`のときのみスキン頂点属性も併せて連結する。
/// NORMAL/TANGENT欠如の計算充填(判断46)は連結後の全体に対して1回だけ行う。
pub(super) fn メッシュデータを取り出す(
    文書: &開いた文書,
    メッシュ: &gltf::Mesh<'_>,
    関節解決: Option<&関節解決>,
    語彙: &材質スロット語彙,
) -> Result<メッシュデータ, アセットコンパイルエラー> {
    let mut 未確定頂点一覧 = Vec::new();
    let mut インデックス一覧 = Vec::new();
    let mut スキン頂点属性一覧 = 関節解決.map(|_| Vec::new());
    let mut プリミティブ列 = Vec::new();

    for プリミティブ in メッシュ.primitives() {
        let 材質スロット = 語彙
            .スロットを参照する(&プリミティブ)
            .ok_or(アセットコンパイルエラー::材質スロット未登録)?;
        let プリミティブデータ = primitive::プリミティブから取り出す(文書, &プリミティブ)?;
        let 頂点ずらし量 = u32::try_from(未確定頂点一覧.len())
            .map_err(|誤り| アセットコンパイルエラー::解析失敗(format!("頂点ずらし量がu32の範囲を超えている: {誤り}")))?;
        let インデックス開始 = インデックス一覧.len();
        インデックス一覧.extend(プリミティブデータ.インデックス一覧.into_iter().map(|添字| 添字 + 頂点ずらし量));
        プリミティブ列.push(メッシュプリミティブ {
            インデックス開始,
            インデックス数: インデックス一覧.len() - インデックス開始,
            頂点基準: 0,
            材質スロット,
        });

        if let (Some(関節解決), Some(格納先)) = (関節解決, スキン頂点属性一覧.as_mut()) {
            let 属性一覧 =
                skin_vertex::プリミティブのスキン属性を取り出す(文書, &プリミティブ, 関節解決, プリミティブデータ.頂点一覧.len())?;
            格納先.extend(属性一覧);
        }

        未確定頂点一覧.extend(プリミティブデータ.頂点一覧);
    }

    let 頂点一覧 = attribute_resolve::頂点属性を確定する(未確定頂点一覧, &インデックス一覧);

    Ok(メッシュデータ {
        頂点一覧,
        インデックス一覧,
        スキン頂点属性一覧,
        プリミティブ列,
    })
}
