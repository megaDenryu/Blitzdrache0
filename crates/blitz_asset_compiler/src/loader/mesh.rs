//! メッシュ内の全プリミティブを頂点ずらし量付きで連結する(判断37)。
//! 個々のプリミティブからの抽出は`primitive`に委ねる。スキンを持つメッシュは
//! ジョイント/ウェイトも同じ頂点順で連結する(判断42)。

