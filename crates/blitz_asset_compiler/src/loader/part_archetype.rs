//! 部品のglTFを、インスタンス群の原型として読み取る工程。受け取るのはカタログと安定ID、
//! 返すのは段1つだけの原型と、材質スロットごとの材質集合である。
//!
//! 群の原型を読む工程と分けるのは、要求する形が正反対だからである。あちらはメッシュを段として並べ、
//! 全段が1つのマテリアルを共有することを求める。部品は1つのメッシュを材質スロットの数だけのプリミティブへ分け、
//! スロットごとに別のマテリアルを持つ。同じ入口へ通すと、段の間のマテリアル一致の検査が部品を必ず落とす。
//!
//! **段を1つしか作らないのは、部品が詳細段を持たないためである。** 段の選択は原型の段数から決まるため、
//! 1段の部品はどの距離でも同じメッシュで描かれる。
//! 参照: `_doc/設計/部品カタログと接合点.md`「実データが暴いた契約の穴」穴3

use blitz_engine::アセットID;

use super::archetype::原型ソース;
use super::{document, material_slots, mesh};
use crate::error::アセットコンパイルエラー;
use crate::scene_compiler::ソースアセットのコンパイル係;

impl ソースアセットのコンパイル係<'_> {
    /// 部品1件を原型として読む。メッシュがちょうど1つであることを求めるのは、部品の入力契約が
    /// 1ファイル1メッシュであり、2つ目のメッシュを黙って捨てると宣言と絵が食い違うためである。
    pub fn 部品の原型ソースを読み込む(&self, id: &アセットID) -> Result<原型ソース, アセットコンパイルエラー> {
        let パス = self.安定idが指すソースのパスを参照する(id)?;
        let 文書 = document::文書を開く(パス)?;
        let メッシュ数 = 文書.document.meshes().count();
        if メッシュ数 != 1 {
            return Err(アセットコンパイルエラー::部品のメッシュ数が1でない { 件数: メッシュ数 });
        }
        let 材質スロット = material_slots::解決する(&文書, 文書.document.meshes(), self.テクスチャの格納方針())?;
        let メッシュ = 文書.document.meshes().next().ok_or(アセットコンパイルエラー::メッシュなし)?;
        let 段 = mesh::メッシュデータを取り出す(&文書, &メッシュ, None, &材質スロット.語彙)?;
        let mut 参照ファイル一覧 = 文書.参照ファイル一覧;
        参照ファイル一覧.extend(材質スロット.参照ファイル一覧);
        Ok(原型ソース {
            段一覧: vec![段],
            材質集合: 材質スロット.材質集合,
            参照ファイル一覧,
        })
    }
}
