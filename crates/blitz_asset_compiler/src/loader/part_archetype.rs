//! 部品のglTFを、インスタンス群の原型として読み取る工程。受け取るのはカタログと安定ID、
//! 返すのは段の列と、材質スロットごとの材質集合である。
//!
//! 群の原型を読む工程と分けるのは、材質への要求が正反対だからである。あちらは全段が1つのマテリアルを共有することを
//! 求める。部品は1つのメッシュを材質スロットの数だけのプリミティブへ分け、スロットごとに別のマテリアルを持つ。
//! 同じ入口へ通すと、段の間のマテリアル一致の検査が部品を必ず落とす。
//!
//! **文書が並べたメッシュをそのまま段の列として読む。** 段を1つしか持たない部品は、その1つが最詳細段になる。
//! 段の選択は原型の段数から決まるため、1段の部品はどの距離でも同じメッシュで描かれる。
//!
//! **接合点は段0のノードだけが宣言する。** 読み取りが先頭メッシュのノードだけを見るためであり、段1以降が
//! 宣言しても無言で捨てられる。捨てられることを違反として捕まえるのは契約の検査の側である。
//! 参照: `_doc/設計/部品カタログと接合点.md`「段(詳細段)は部品の側へ持たせる」

use blitz_engine::アセットID;

use super::archetype::原型ソース;
use super::{document, material_slots, mesh};
use crate::error::アセットコンパイルエラー;
use crate::scene_compiler::ソースアセットのコンパイル係;

impl ソースアセットのコンパイル係<'_> {
    /// 部品1件を原型として読む。メッシュが1つも無い文書を拒むのは、段を1つも持たない原型を焼けないためである。
    /// 材質スロットの語彙を全段のプリミティブから作るのは、遠距離段が近距離段の材質の一部だけを使う形を許すためである。
    pub fn 部品の原型ソースを読み込む(&self, id: &アセットID) -> Result<原型ソース, アセットコンパイルエラー> {
        let パス = self.安定idが指すソースのパスを参照する(id)?;
        let 文書 = document::文書を開く(パス)?;
        if 文書.document.meshes().next().is_none() {
            return Err(アセットコンパイルエラー::部品にメッシュが1つも無い);
        }
        let 材質スロット = material_slots::解決する(&文書, 文書.document.meshes(), self.テクスチャの格納方針())?;
        let mut 段一覧 = Vec::new();
        for メッシュ in 文書.document.meshes() {
            段一覧.push(mesh::メッシュデータを取り出す(&文書, &メッシュ, None, &材質スロット.語彙)?);
        }
        let mut 参照ファイル一覧 = 文書.参照ファイル一覧;
        参照ファイル一覧.extend(材質スロット.参照ファイル一覧);
        Ok(原型ソース {
            段一覧,
            材質集合: 材質スロット.材質集合,
            参照ファイル一覧,
        })
    }
}
