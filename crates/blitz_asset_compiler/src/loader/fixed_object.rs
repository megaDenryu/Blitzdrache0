//! カタログのglTFを、呼び出し側が決めた描画対象番号と配置変換で1つの描画対象として読み込む工程。
//! 受け取るのはカタログと安定IDと所有チャンクと描画対象番号と配置変換、返すのは描画対象と参照ファイル一覧である。
//!
//! スキンとアニメーションを読まないのは、この入口が地面へ据え置く固定物のためである。骨を持つシーンは
//! `ソースシーンを読み込む`が扱い、あちらは描画対象番号も配置変換も自分で決める(単独のシーンとして焼くためである)。
//! 先頭メッシュの全プリミティブを1つの描画対象へ連結するのは、材質の境目をプリミティブの境目として残すためである。

use std::path::PathBuf;

use blitz_engine::{アセットID, カタログ, チャンク座標, 描画対象ID, 描画対象データ, 描画形状};
use blitz_math::{ローカル, ワールド, 変換};

use super::{document, material_slots, mesh};
use crate::error::アセットコンパイルエラー;

pub(crate) fn 固定物の描画対象を読み込む(
    カタログ: &カタログ,
    id: &アセットID,
    所有チャンク: チャンク座標,
    描画対象番号: u64,
    ローカルからワールド: 変換<ローカル, ワールド>,
) -> Result<(描画対象データ, Vec<PathBuf>), アセットコンパイルエラー> {
    let パス = カタログ
        .パスを参照する(id)
        .ok_or_else(|| アセットコンパイルエラー::カタログ未登録(id.clone()))?;
    let 開いた文書 = document::文書を開く(パス)?;
    let 対象メッシュ = 開いた文書.document.meshes().next().ok_or(アセットコンパイルエラー::メッシュなし)?;
    if 対象メッシュ.primitives().next().is_none() {
        return Err(アセットコンパイルエラー::プリミティブなし);
    }
    let 材質スロット = material_slots::解決する(&開いた文書, std::iter::once(対象メッシュ.clone()))?;
    let メッシュ実体 = mesh::メッシュデータを取り出す(&開いた文書, &対象メッシュ, None, &材質スロット.語彙)?;
    let mut 参照ファイル一覧 = 開いた文書.参照ファイル一覧;
    参照ファイル一覧.extend(材質スロット.参照ファイル一覧);
    let 描画対象 = 描画対象データ::生成する(
        描画対象ID::生成する(描画対象番号),
        所有チャンク,
        ローカルからワールド,
        描画形状::通常メッシュ(メッシュ実体),
        材質スロット.材質集合,
    );
    Ok((描画対象, 参照ファイル一覧))
}
