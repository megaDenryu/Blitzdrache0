//! 原型の全LOD段が1つのマテリアルを共有していることの検査。受け取るのはソースglTFの文書、返すのは受理か型付きエラーかである。
//! バッファ実体を読まないため、ジオメトリの読取より前に走らせられる。
//!
//! 原型はマテリアルを段ごとに持たず、外側の描画対象データが1つだけ持つ(参照: `_doc/設計/植生インスタンスと物量計測.md`「インスタンス群の表現」)。
//! そのため読取は先頭メッシュの先頭プリミティブのマテリアルだけを採る。段ごとに違うマテリアルを宣言したソースを
//! そのまま通すと、先頭段のマテリアルが残りの段へ無言で適用され、焼いた絵が作者の宣言と食い違う。
//! 段ごとにマテリアルを変えられるようにするには描画対象データの側の形を変えることになるため、
//! ここでは全段同一を形式契約として要求し、破れを入力の境界で拒む。
//!
//! 揃っていることを見るのはマテリアルの参照先と、そのマテリアルが読むUV座標(TEXCOORD_0)の有無である。
//! 法線と接線の有無は見ない。欠けていればコンパイラが頂点から計算して充填する経路が既にあり、
//! 段ごとに違うジオメトリを持つ原型ではその結果が段ごとに違うことが正常だからである。

use crate::error::アセットコンパイルエラー;

/// 1つのプリミティブが宣言する、段の間で揃っていなければならない条件。
/// マテリアル番号がglTFのマテリアル配列の添字であり、宣言なし(既定マテリアル)は`None`として区別する。
#[derive(PartialEq, Eq, Clone, Copy)]
struct 段の描画条件 {
    マテリアル番号: Option<usize>,
    uv座標を持つ: bool,
}

impl 段の描画条件 {
    fn 読み取る(プリミティブ: &gltf::Primitive<'_>) -> Self {
        Self {
            マテリアル番号: プリミティブ.material().index(),
            uv座標を持つ: プリミティブ.get(&gltf::Semantic::TexCoords(0)).is_some(),
        }
    }
}

/// 段番号は文書が並べたメッシュの順であり、先頭が最詳細段である。
pub(super) fn 全段が同じ描画条件かを検査する(document: &gltf::Document) -> Result<(), アセットコンパイルエラー> {
    let mut 先頭段の条件: Option<段の描画条件> = None;
    for (段番号, メッシュ) in document.meshes().enumerate() {
        for プリミティブ in メッシュ.primitives() {
            let 条件 = 段の描画条件::読み取る(&プリミティブ);
            let Some(先頭) = 先頭段の条件 else {
                先頭段の条件 = Some(条件);
                continue;
            };
            段と先頭を突き合わせる(段番号, 先頭, 条件)?;
        }
    }
    Ok(())
}

fn 段と先頭を突き合わせる(
    段番号: usize, 先頭: 段の描画条件, 条件: 段の描画条件
) -> Result<(), アセットコンパイルエラー> {
    if 先頭.マテリアル番号 != 条件.マテリアル番号 {
        return Err(アセットコンパイルエラー::原型の段間マテリアル不一致 { 段番号 });
    }
    if 先頭.uv座標を持つ != 条件.uv座標を持つ {
        return Err(アセットコンパイルエラー::原型の段間UV有無不一致 { 段番号 });
    }
    Ok(())
}
