//! 焼いた結果が入力のプリミティブを1件も落としていないことの検査。受け取るのはglTFの先頭メッシュのプリミティブ数と焼いたメッシュデータ、返すのは指摘一覧である。
//!
//! マルチマテリアル対応より前は、先頭プリミティブと違うマテリアルを参照するプリミティブを違反として拒んでいた。
//! 拒む理由は、ローダーが先頭のマテリアルをメッシュ全体へ適用し、2番目以降の材質の宣言が絵に出ないことにあった。
//! 今のローダーはプリミティブごとに材質スロットを残して全件を焼くため、その拒否は成り立たない。
//! 代わりに置くのがこの検査であり、入力のプリミティブが1件残らず焼いた結果へ現れることを見る。
//!
//! この判定はローダーの事後条件の言い直しであり、いま受け取れる入力では発火しない。それでも置くのは、この検査器が契約の正本である
//! ローダーから導かれる道具であり、ローダーがプリミティブを落とすようになったときに絵を見るより先にここで止めるためである。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「Blender段4までの受理範囲」

use blitz_engine::メッシュデータ;

use super::finding::契約指摘;
use super::target::対象位置;

pub(super) fn 検査する(入力プリミティブ数: usize, データ: &メッシュデータ) -> Vec<契約指摘> {
    let 焼いた件数 = データ.プリミティブ列.len();
    if 焼いた件数 == 入力プリミティブ数 {
        return Vec::new();
    }
    vec![契約指摘::違反を作る(
        対象位置::メッシュ { 添字: 0, 名前: None },
        format!("プリミティブ{入力プリミティブ数}個のうち焼かれたのは{焼いた件数}個である。焼かれなかったプリミティブの面は絵に出ない"),
        "Blenderから書き出し直す。手で編集したglTFでプリミティブの並びが壊れていないかを確かめる",
    )]
}
