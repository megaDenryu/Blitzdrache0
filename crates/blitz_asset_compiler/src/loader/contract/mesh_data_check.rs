//! 読み終えたメッシュデータが実行時形式の要求を満たすかの判定。受け取るのは連結済みのメッシュデータ、返すのは指摘一覧である。
//! 由来は`blitz_engine`の実行時形式が頂点0件・インデックス0件・範囲外インデックス・非有限の小数を型付きエラーで拒むことである。
//! インデックス数が3の倍数であることは、ローダーが並び方を三角形リストと決めていることから従う。

use blitz_engine::メッシュデータ;

use super::finding::契約指摘;
use super::target::対象位置;

pub(super) fn 検査する(データ: &メッシュデータ) -> Vec<契約指摘> {
    let 頂点数 = データ.頂点一覧.len();
    let インデックス数 = データ.インデックス一覧.len();
    if 頂点数 == 0 || インデックス数 == 0 {
        return vec![契約指摘::違反を作る(
            位置(),
            format!("頂点{頂点数}個、インデックス{インデックス数}個である。実行時形式は1頂点1インデックス以上を要求する"),
            "面を持つメッシュを書き出す",
        )];
    }

    let mut 指摘一覧 = Vec::new();
    if !インデックス数.is_multiple_of(3) {
        指摘一覧.push(契約指摘::違反を作る(
            位置(),
            format!("インデックスが{インデックス数}個で3の倍数でない。ローダーは三角形リストとして渡す"),
            "Blenderの書き出し設定で三角形化を有効にする",
        ));
    }
    範囲外インデックスを検査する(&mut 指摘一覧, データ, 頂点数);
    非有限小数を検査する(&mut 指摘一覧, データ);
    指摘一覧
}

fn 範囲外インデックスを検査する(指摘一覧: &mut Vec<契約指摘>, データ: &メッシュデータ, 頂点数: usize) {
    let Some(&最大添字) = データ.インデックス一覧.iter().max() else {
        return;
    };
    if usize::try_from(最大添字).is_ok_and(|値| 値 < 頂点数) {
        return;
    }
    指摘一覧.push(契約指摘::違反を作る(
        位置(),
        format!("インデックスの最大値{最大添字}が頂点数{頂点数}の範囲外である"),
        "Blenderから書き出し直す。手で編集したglTFのアクセサの件数とバッファビューの長さが合っているかを確かめる",
    ));
}

fn 非有限小数を検査する(指摘一覧: &mut Vec<契約指摘>, データ: &メッシュデータ) {
    let 非有限がある = データ.頂点一覧.iter().any(|頂点| {
        let mut 全成分 = 頂点.位置.iter().chain(頂点.法線.iter()).chain(頂点.接線.iter()).chain(頂点.uv.iter());
        全成分.any(|成分| !成分.is_finite())
    });
    if !非有限がある {
        return;
    }
    指摘一覧.push(契約指摘::違反を作る(
        位置(),
        "頂点属性に非有限の小数(NaNまたは無限)が含まれる。実行時形式は非有限の小数を拒む",
        "Blenderで頂点が重なった面・面積0の面・不正なUVを取り除いてから書き出す",
    ));
}

/// 判定はローダーが読む先頭メッシュだけを対象にするため、位置は常に先頭メッシュを指す。
fn 位置() -> 対象位置 {
    対象位置::メッシュ { 添字: 0, 名前: None }
}
