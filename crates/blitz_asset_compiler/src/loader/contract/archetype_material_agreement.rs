//! 段の間でマテリアルとUV座標の有無が揃っていることの検査。担当するのは、コンパイラが入力の境界で使っている判定を
//! そのまま走らせ、その型付きエラーを1件の指摘へ写すことだけである。
//!
//! 判定を書き直さないのは、揃っていることの規則の正本が`archetype_material`であり、写しを持つと片方だけが直るためである。
//! 原型はマテリアルを段ごとに持たず、外側の描画対象データが1つだけ持つ。段ごとに違うマテリアルを宣言したソースを通すと、
//! 先頭段のマテリアルが残りの段へ無言で適用される。

use super::super::archetype_material;
use super::inspection::開いた文書の契約検査;
use super::target::対象位置;

impl 開いた文書の契約検査<'_> {
    pub(super) fn 段の間で描画条件が揃うことを検査する(&mut self) {
        let Err(誤り) = archetype_material::全段が同じ描画条件かを検査する(self.文書の全体()) else {
            return;
        };
        self.違反を記す(
            対象位置::文書,
            format!("段の間で描画条件が揃っていない: {誤り}"),
            "全ての段へ同じ1つのマテリアルを割り当て、UV展開の有無も段の間で揃える。Blenderでは最詳細段のマテリアルを他の段へ複製して割り当てる",
        );
    }
}
