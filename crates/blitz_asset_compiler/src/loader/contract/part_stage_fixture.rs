//! 段の列を持つ部品の試験材料。担当するのは、接合点を載せたノード列と、1つの段が複数のプリミティブを持つ段の綴りである。
//! 段そのものの綴りと文書とバイナリは`archetype_fixture`が持ち、この材料はそこへ差し込む2箇所だけを足す。
//!
//! 接合点の宣言を1件だけにするのは、この試験が見るのが段の並べ方と接合点をどの段が持つかであり、
//! 宣言の中身の破れは`joint_tests`が既に持っているためである。位置は段の境界箱(最小[-1, 0, -1]・最大[1, 2, 1])の内側にある。

/// 段の列の材料の境界箱の内側に置いた、どの検査項目にも触れない接合点1件。
const 合格の接合点: &str = concat!(
    r#"{ "名前": "上面", "種別": "上面積層", "位置": [0.5, 0.5, 0.0], "向き": [0.0, 1.0, 0.0], "#,
    r#""上方向": [0.0, 0.0, 1.0], "接合面": { "幅": 1.0, "高さ": 1.0 } }"#
);

/// 段0だけが接合点を宣言する1ノード。段を1つしか持たない部品はこの形である。
pub(super) fn 接合点を持つ1ノード() -> String {
    format!(r#"{{ "mesh": 0, "extras": {{ "接合点": [ {合格の接合点} ] }} }}"#)
}

/// 段0だけが接合点を宣言する2ノード。段の列を持つ部品の正しい形である。
pub(super) fn 段0だけが接合点を持つ2ノード() -> String {
    format!(r#"{{ "mesh": 0, "extras": {{ "接合点": [ {合格の接合点} ] }} }}, {{ "mesh": 1 }}"#)
}

/// 段0と段1の両方が接合点を宣言する2ノード。段1の宣言は読まれずに捨てられる。
pub(super) fn 両方の段が接合点を持つ2ノード() -> String {
    let ノード = format!(r#"{{ "mesh": 0, "extras": {{ "接合点": [ {合格の接合点} ] }} }}"#);
    let 段1 = format!(r#"{{ "mesh": 1, "extras": {{ "接合点": [ {合格の接合点} ] }} }}"#);
    format!("{ノード}, {段1}")
}

/// 1つの段が2つのプリミティブへ分かれた段。部品は材質スロットの数だけプリミティブへ分かれるため、この形が正しい。
pub(super) const プリミティブ2つの段: &str = concat!(
    r#"{ "name": "プリミティブ2つの段", "primitives": [ "#,
    r#"{ "attributes": { "POSITION": 0, "NORMAL": 2, "TEXCOORD_0": 3 }, "indices": 4, "material": 0 }, "#,
    r#"{ "attributes": { "POSITION": 0, "NORMAL": 2, "TEXCOORD_0": 3 }, "indices": 5, "material": 0 } ] }"#
);
