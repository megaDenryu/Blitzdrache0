//! メッシュの境界箱: 1つのメッシュが占める軸平行の直方体。アクセサが宣言する頂点位置の最小と最大から読み、バッファ実体は読まない。
//!
//! `gltf::Primitive::bounding_box`を呼ばないのは、頂点位置の属性が無い文書と最小・最大の宣言が欠けた文書でその関数がpanicするためである。
//! 検査器は壊れた入力を読まされる側であり、壊れ方は型付きの理由で返さなければならない。読む出どころは同じアクセサの宣言である。
//!
//! 原点からのずれをこの型のメソッドで答えるのは、成分の足し引きが「原点が接地面の中央に在るか」という1つの問いの内訳であり、
//! 呼び出し側が最小と最大の生の配列を受け取って組み立て直すと、軸の取り違えが型を通ってしまうためである。

/// メッシュの境界箱を宣言から読めない事情。どれも作者が書き出しでやり直すべき破れである。
pub(super) enum 境界箱を読めない理由 {
    プリミティブが1つも無い,
    頂点位置の属性が無い,
    頂点位置の最小か最大の宣言が無い,
    頂点位置の最小か最大を3つの小数として読めない,
}

pub(super) struct メッシュの境界箱 {
    最小: [f32; 3],
    最大: [f32; 3],
}

impl メッシュの境界箱 {
    /// メッシュの全プリミティブの箱を合わせた1つの箱を読む。
    pub(super) fn メッシュのアクセサの宣言から読む(メッシュ: &gltf::Mesh<'_>) -> Result<Self, 境界箱を読めない理由> {
        let mut 合わせた箱: Option<Self> = None;
        for プリミティブ in メッシュ.primitives() {
            let 箱 = Self::プリミティブのアクセサの宣言から読む(&プリミティブ)?;
            合わせた箱 = Some(match 合わせた箱 {
                Some(これまで) => これまで.合わせる(&箱),
                None => 箱,
            });
        }
        合わせた箱.ok_or(境界箱を読めない理由::プリミティブが1つも無い)
    }

    /// glTFはY軸を上とするため、底面の高さはY成分の最小である。接地しているならこれが0になる。
    pub(super) fn 底面の高さ(&self) -> f32 {
        self.最小[1]
    }

    /// X軸方向の中心が原点からどれだけ離れているか。最小と最大の和が中心の2倍であり、中央に在れば0になる。
    pub(super) fn x軸方向の中心の原点からのずれ(&self) -> f32 {
        self.最小[0] + self.最大[0]
    }

    pub(super) fn z軸方向の中心の原点からのずれ(&self) -> f32 {
        self.最小[2] + self.最大[2]
    }

    /// この箱の周りで位置を突き合わせるときの許容差。座標はf32であり、f32は仮数部の桁数が固定であるから、表せる値の刻みは
    /// 値の大きさに比例する。この箱の大きさの位置で表せる最小の刻みは、最大の辺の長さと`f32::EPSILON`の積である。
    /// それより小さいずれは0と区別できないため、この積をそのまま許容差にする。
    pub(super) fn 箱の大きさが決める許容差(&self) -> f32 {
        self.最大の辺の長さ() * f32::EPSILON
    }

    /// 点が箱の内側か面上にあるか。接合点は面の上に置かれることが多いため、境界を含める。
    pub(super) fn 点を含むか(&self, 点: [f32; 3]) -> bool {
        let 許容差 = self.箱の大きさが決める許容差();
        (0..3).all(|軸| 点[軸] >= self.最小[軸] - 許容差 && 点[軸] <= self.最大[軸] + 許容差)
    }

    fn 最大の辺の長さ(&self) -> f32 {
        let 辺の長さ = [self.最大[0] - self.最小[0], self.最大[1] - self.最小[1], self.最大[2] - self.最小[2]];
        辺の長さ.iter().fold(0.0_f32, |これまで, 長さ| これまで.max(*長さ))
    }

    fn 合わせる(&self, 他: &Self) -> Self {
        let mut 最小 = self.最小;
        let mut 最大 = self.最大;
        for 軸 in 0..3 {
            最小[軸] = 最小[軸].min(他.最小[軸]);
            最大[軸] = 最大[軸].max(他.最大[軸]);
        }
        Self { 最小, 最大 }
    }

    fn プリミティブのアクセサの宣言から読む(
        プリミティブ: &gltf::Primitive<'_>
    ) -> Result<Self, 境界箱を読めない理由> {
        let 位置アクセサ = プリミティブ
            .get(&gltf::Semantic::Positions)
            .ok_or(境界箱を読めない理由::頂点位置の属性が無い)?;
        Ok(Self {
            最小: 宣言を3つの小数として読む(位置アクセサ.min())?,
            最大: 宣言を3つの小数として読む(位置アクセサ.max())?,
        })
    }
}

fn 宣言を3つの小数として読む(宣言: Option<gltf::json::Value>) -> Result<[f32; 3], 境界箱を読めない理由> {
    let 値 = 宣言.ok_or(境界箱を読めない理由::頂点位置の最小か最大の宣言が無い)?;
    gltf::json::deserialize::from_value(値)
        .map_err(|_誤り| 境界箱を読めない理由::頂点位置の最小か最大を3つの小数として読めない)
}
