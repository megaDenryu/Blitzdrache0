//! ベースカラーが白のまま焼かれる材質の検査。3つの契約すべてへ課す。
//!
//! glTFの既定のベースカラー係数は白(1, 1, 1, 1)である。テクスチャがあれば、この白はテクスチャへ掛かる中立の倍率として
//! 正しく働く。テクスチャが無いと白がそのまま色になり、作者が意図した色を持たない真っ白な面が焼ける。
//! **焼けても作者の宣言と絵が食い違うことが確定するため、警告でなく違反である。**
//!
//! 注意: 見るのは綴りの有無でなく焼ける結果である。`gltf`は宣言が無いときに既定の白を埋めるため、係数が書かれていたのか
//! 既定が当たったのかをこの層から区別できない。区別できたとしても、どちらも真っ白な面が焼ける点で欠陥は同じである。
//!
//! マテリアルを宣言していないプリミティブを対象から外すのは、群の原型が材質を持たない形で正当に成立し、
//! 色を`archetype_material`が後から与えるためである。宣言が無いことの是非は`material_declaration_scan`が見る。

use super::inspection::開いた文書の契約検査;
use super::slot_materials::材質スロットの参照;
use super::target::{名前を写す, 対象位置};

/// 白と見なす係数。glTFの既定そのものであり、この値のときだけ「色が与えられていない」と判定する。
const 白の係数: [f32; 4] = [1.0, 1.0, 1.0, 1.0];

impl 開いた文書の契約検査<'_> {
    pub(super) fn ベースカラーが白のままの材質を検査する(&mut self, 材質スロット一覧: &[材質スロットの参照<'_>]) {
        for スロット in 材質スロット一覧 {
            self.スロット1つのベースカラーを検査する(スロット);
        }
    }

    fn スロット1つのベースカラーを検査する(&mut self, スロット: &材質スロットの参照<'_>) {
        let マテリアル = スロット.プリミティブ.material();
        if マテリアル.index().is_none() {
            return;
        }
        let 金属粗さ = マテリアル.pbr_metallic_roughness();
        if 金属粗さ.base_color_texture().is_some() || 金属粗さ.base_color_factor() != 白の係数 {
            return;
        }
        self.違反を記す(
            対象位置::マテリアル {
                スロット: スロット.番号,
                名前: 名前を写す(マテリアル.name()),
            },
            "ベースカラーのテクスチャも係数も無いため、この材質は真っ白に焼ける。作者が与えた色が絵に出ない",
            "Blenderのプリンシプル BSDF のベースカラーへ色を与えるか、ベースカラーのテクスチャを割り当ててから書き出し直す",
        );
    }
}
