//! 接合点の宣言の検査。担当するのは、宣言が1件以上あることと、宣言ごとの読み取りの破れを指摘へ写すことである。
//!
//! 何が破れかの正本は読み取りの側(`loader::joint`)にある。種別の綴り・向きと上方向の単位長と直交・接合面の寸法は、
//! すべて読み取りが型付きエラーで拒む。ここが同じ規則を書き直すと正本が2つになる。この工程は破れを指摘の文面へ写すだけである。
//!
//! 宣言が0件を違反にするのは部品の契約でだけである。`--part`を付けて呼ばれた以上、0件は書き出し設定の
//! `export_extras`の付け忘れであり、警告にすると終了コードに出ず運用者が見落とす。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合点の検査項目」

use super::super::joint::{接合点の読み取りの成否, 部品の接合点の読み取り};
use super::inspection::開いた文書の契約検査;
use super::target::対象位置;

impl 開いた文書の契約検査<'_> {
    pub(super) fn 接合点の宣言を検査する(&mut self) {
        let 読み取り = match 部品の接合点の読み取り::先頭メッシュのノードから読み取る(self.文書の全体()) {
            Ok(読み取り) => 読み取り,
            Err(誤り) => {
                self.違反を記す(
                    対象位置::文書,
                    format!("接合点の宣言を読み取れなかった: {誤り}"),
                    "Blender側でオブジェクトのカスタムプロパティ「接合点」へ辞書の配列を代入し、書き出しで export_extras=True を明示する",
                );
                return;
            }
        };
        self.宣言が1件以上あることを検査する(&読み取り);
        self.宣言ごとの読み取りの破れを記す(&読み取り);
        self.接合点の名前が一意であることを検査する(&読み取り);
        self.接合点の位置が境界箱の内側にあることを検査する(&読み取り);
    }

    fn 宣言が1件以上あることを検査する(&mut self, 読み取り: &部品の接合点の読み取り) {
        if 読み取り.宣言の件数() > 0 {
            return;
        }
        self.違反を記す(
            対象位置::文書,
            "接合点の宣言が1件も無い。部品として検査しているため、これは書き出し設定の付け忘れである",
            "Blenderの書き出しで export_extras=True を明示し、オブジェクトのカスタムプロパティ「接合点」を設定してから書き出し直す",
        );
    }

    fn 宣言ごとの読み取りの破れを記す(&mut self, 読み取り: &部品の接合点の読み取り) {
        for 成否 in 読み取り.宣言ごとの結果() {
            let 接合点の読み取りの成否::読めなかった { 宣言の添字, 誤り } = 成否 else {
                continue;
            };
            self.違反を記す(
                対象位置::接合点 {
                    添字: *宣言の添字,
                    名前: None,
                },
                format!("接合点の宣言を接合点として読めない: {誤り}"),
                "Blender側の接合点の登録で、種別を既知の綴りにし、向きと上方向を長さ1で互いに直交させ、接合面の幅と高さを正の有限値にする",
            );
        }
    }
}
