#[test]
fn 段のノードが変換を持てば違反になる() {
    let メッシュ列 = 段を並べる(&[接地した三角形2つの段, 接地した三角形1つの段]);
    let ノード列 = r#"{ "mesh": 0, "translation": [3.0, 0.0, 0.0] }, { "mesh": 1 }"#;
    let 結果 = 原型として検査する("原型のノード変換あり", &段の列の指定(&メッシュ列, ノード列));
    assert!(!結果.合格か(), "指摘: {結果}");
    assert_eq!(結果.違反件数(), 1, "指摘: {結果}");
}

/// 段の間の描画条件の判定は`archetype_material`が正本であり、ここで見るのはその破れ(この材料ではUV座標の有無の食い違い)が指摘1件として読み手へ届くことである。
#[test]
