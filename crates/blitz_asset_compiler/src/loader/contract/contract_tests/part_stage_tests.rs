//! 段の列を持つ部品の契約の試験。合格する段の列と、部品の契約を1箇所だけ崩した負の対照を突き合わせる。
//!
//! 段を持たない部品の試験は`joint_tests`が持つ。こちらが見るのは、段の列を受け入れることと、
//! 段の並びの規則が部品でも走ること、接合点を宣言してよいのが段0だけであること、そして
//! **群の原型と違って段ごとに複数のプリミティブを許すこと**の4つである。

use super::super::archetype_fixture::{原型の文書の指定, 接地した三角形1つの段, 接地した三角形2つの段, 段を並べる};
use super::super::part_stage_fixture::{
    プリミティブ2つの段, 両方の段が接合点を持つ2ノード, 接合点を持つ1ノード, 段0だけが接合点を持つ2ノード
};
use super::部品の段の列として検査する;

fn 段の列の指定<'材料>(メッシュ列: &'材料 str, ノード列: &'材料 str) -> 原型の文書の指定<'材料> {
    原型の文書の指定 {
        メッシュ列, ノード列
    }
}

#[test]
fn 詳細な順に並んだ2段の部品は違反も警告も出ない() {
    let メッシュ列 = 段を並べる(&[接地した三角形2つの段, 接地した三角形1つの段]);
    let ノード列 = 段0だけが接合点を持つ2ノード();
    let 結果 = 部品の段の列として検査する("部品の2段が合格", &段の列の指定(&メッシュ列, &ノード列));
    assert!(結果.合格か(), "指摘: {結果}");
    assert_eq!(結果.警告件数(), 0, "指摘: {結果}");
    assert_eq!(結果.概要().unwrap().メッシュ数, 2);
}

/// 段を1つしか持たない部品は今の実データの形である。段の列を受け入れる拡張が、この形を落としてはならない。
#[test]
fn 段を1つしか持たない部品も合格する() {
    let メッシュ列 = 段を並べる(&[接地した三角形2つの段]);
    let ノード列 = 接合点を持つ1ノード();
    let 結果 = 部品の段の列として検査する("部品の1段が合格", &段の列の指定(&メッシュ列, &ノード列));
    assert!(結果.合格か(), "指摘: {結果}");
    assert_eq!(結果.警告件数(), 0, "指摘: {結果}");
}

#[test]
fn 三角形数が段の順に増えていれば違反になる() {
    let メッシュ列 = 段を並べる(&[接地した三角形1つの段, 接地した三角形2つの段]);
    let ノード列 = 段0だけが接合点を持つ2ノード();
    let 結果 = 部品の段の列として検査する("部品の段の順が逆", &段の列の指定(&メッシュ列, &ノード列));
    assert!(!結果.合格か(), "指摘: {結果}");
    assert_eq!(結果.違反件数(), 1, "指摘: {結果}");
}

/// 段1の宣言は読み取りが一度も見ないため、宣言と絵が食い違う。
#[test]
fn 段0以外が接合点を宣言すれば違反になる() {
    let メッシュ列 = 段を並べる(&[接地した三角形2つの段, 接地した三角形1つの段]);
    let ノード列 = 両方の段が接合点を持つ2ノード();
    let 結果 = 部品の段の列として検査する("部品の段1が接合点を持つ", &段の列の指定(&メッシュ列, &ノード列));
    assert!(!結果.合格か(), "指摘: {結果}");
    assert_eq!(結果.違反件数(), 1, "指摘: {結果}");
}

