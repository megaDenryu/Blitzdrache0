//! 部品の契約の試験。合格する材料と、接合点の契約を1箇所だけ崩した負の対照を突き合わせる。
//!
//! 材料の三角形の境界箱は最小[0, 0, 0]・最大[1, 1, 0]である。位置の検査の対照はこの箱を基準に作る。
//! 節点のextrasを載せた材料をここで組み立てるのは、glbのバイト列まで通す経路を持つのがこの階層だけであり、
//! 読み取りの側の試験(`loader::joint`)は宣言1件を見るところまでを持つためである。

use super::super::fixture_json::{合格の指定, 文書の指定};
use super::検査する契約;
use super::{glbを書き出す, 三角形のバイナリ, 入力契約を検査するglTFのファイル, 契約検査結果, 文書jsonを作る};

/// 箱の内側に位置を置いた、どの検査項目にも触れない接合点1件を持つノード。
const 合格のノード列: &str = concat!(
    r#"{ "mesh": 0, "extras": { "接合点": [ "#,
    r#"{ "名前": "上面", "種別": "上面積層", "位置": [0.5, 0.5, 0.0], "向き": [0.0, 1.0, 0.0], "#,
    r#""上方向": [0.0, 0.0, 1.0], "接合面": { "幅": 1.0, "高さ": 1.0 } } ] } }"#
);

fn 部品として検査する(名前: &str, 指定: &文書の指定<'_>) -> 契約検査結果 {
    let パス = glbを書き出す(名前, &文書jsonを作る(指定), &三角形のバイナリ()).unwrap();
    入力契約を検査するglTFのファイル::生成する(&パス).契約を選んで全項目を検査する(検査する契約::部品)
}

fn 接合点を1件だけ持つ指定(接合点: &str) -> String {
    format!(r#"{{ "mesh": 0, "extras": {{ "接合点": [ {接合点} ] }} }}"#)
}

#[test]
fn 契約を満たす接合点は違反も警告も出ない() {
    let mut 指定 = 合格の指定();
    指定.ノード列 = 合格のノード列;
    let 結果 = 部品として検査する("部品合格", &指定);
    assert!(結果.合格か(), "指摘: {結果}");
    assert_eq!(結果.警告件数(), 0, "指摘: {結果}");
}

/// 書き出し設定の付け忘れをここで止める。警告にすると終了コードに出ず運用者が見落とす。
#[test]
fn 接合点の宣言が1件も無ければ違反になる() {
    let 結果 = 部品として検査する("部品の接合点なし", &合格の指定());
    assert!(!結果.合格か(), "指摘: {結果}");
    assert_eq!(結果.違反件数(), 1, "指摘: {結果}");
}

