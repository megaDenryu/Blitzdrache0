//! 材質スロットの契約の試験。担当するのは、1メッシュが複数の材質を持てるようになったことで変わった判定の正負両方の確認である。
//! 見るのは3つである。複数材質を受け入れること、材質の割り当て忘れを拒むこと、そして先頭以外の材質の宣言も先頭と同じ厳しさで見ることである。
//! 3つめが要るのは、先頭の材質だけを見る実装だと2番目以降の材質の破れが黙って通り、作者の宣言と絵が食い違うためである。

use super::super::fixture_json::{三角形のプリミティブ, 不透明の茶色, 二材質の指定, 合格の指定};
use super::検査する;

#[test]
fn 材質を2つ持つメッシュは違反も警告も出ない() {
    let 結果 = 検査する("二材質", &二材質の指定());
    assert!(結果.合格か(), "指摘: {結果}");
    assert_eq!(結果.違反件数(), 0, "指摘: {結果}");
    assert_eq!(結果.警告件数(), 0, "指摘: {結果}");
    assert_eq!(結果.概要().unwrap().プリミティブ数, 2);
}

#[test]
fn 一部のプリミティブだけがマテリアルを宣言していなければ違反になる() {
    let mut 指定 = 合格の指定();
    let プリミティブ列 = format!("{三角形のプリミティブ}, {マテリアルなしの三角形}");
    指定.プリミティブ列 = &プリミティブ列;
    let 結果 = 検査する("材質の割り当て忘れ", &指定);
    assert!(!結果.合格か(), "指摘: {結果}");
    assert_eq!(結果.違反件数(), 1, "指摘: {結果}");
}

#[test]
fn 全プリミティブがマテリアルを宣言していなければ警告になる() {
    let mut 指定 = 合格の指定();
    指定.プリミティブ列 = マテリアルなしの三角形;
    let 結果 = 検査する("マテリアル未宣言", &指定);
    assert!(結果.合格か(), "指摘: {結果}");
    // 未宣言そのものの警告に、glTFの既定マテリアルが片面表示であることの警告が続く。
    assert_eq!(結果.警告件数(), 2, "指摘: {結果}");
}

const マテリアルなしの三角形: &str = r#"{ "attributes": { "POSITION": 0, "NORMAL": 1, "TEXCOORD_0": 2 }, "indices": 3 }"#;

#[test]
fn 二番目の材質の係数が範囲外なら違反になる() {
    let mut 指定 = 二材質の指定();
    let マテリアル列 = format!(
        r#"{不透明の茶色}, {{ "doubleSided": true, "pbrMetallicRoughness": {{ "baseColorFactor": [0.1, 0.2, 0.9, 1.0], "metallicFactor": 2.0, "roughnessFactor": 0.3 }} }}"#
    );
    指定.マテリアル列 = &マテリアル列;
    let 結果 = 検査する("二番目の係数が範囲外", &指定);
    assert!(!結果.合格か(), "指摘: {結果}");
    assert_eq!(結果.違反件数(), 1, "指摘: {結果}");
}

#[test]
fn 二番目の材質の発光は警告になる() {
    let mut 指定 = 二材質の指定();
    let マテリアル列 = format!(
        r#"{不透明の茶色}, {{ "doubleSided": true, "emissiveFactor": [1.0, 0.5, 0.0], "pbrMetallicRoughness": {{ "baseColorFactor": [0.1, 0.2, 0.9, 1.0], "metallicFactor": 1.0, "roughnessFactor": 0.3 }} }}"#
    );
    指定.マテリアル列 = &マテリアル列;
    let 結果 = 検査する("二番目の材質が発光", &指定);
    assert!(結果.合格か(), "指摘: {結果}");
    assert_eq!(結果.警告件数(), 1, "指摘: {結果}");
}

#[test]
fn 同じ材質を参照するプリミティブが2つでも指摘は畳まれる() {
    let mut 指定 = 合格の指定();
    let プリミティブ列 = format!("{三角形のプリミティブ}, {三角形のプリミティブ}");
    指定.プリミティブ列 = &プリミティブ列;
    let 結果 = 検査する("同じ材質の2プリミティブ", &指定);
    assert!(結果.合格か(), "指摘: {結果}");
    assert_eq!(結果.警告件数(), 0, "指摘: {結果}");
    assert_eq!(結果.概要().unwrap().プリミティブ数, 2);
}

#[test]
fn 二番目の材質だけが片面表示でも警告になる() {
    let mut 指定 = 二材質の指定();
    let マテリアル列 = format!(
        r#"{不透明の茶色}, {{ "pbrMetallicRoughness": {{ "baseColorFactor": [0.1, 0.2, 0.9, 1.0], "metallicFactor": 1.0, "roughnessFactor": 0.3 }} }}"#
    );
    指定.マテリアル列 = &マテリアル列;
    let 結果 = 検査する("二番目の材質が片面表示", &指定);
    assert_eq!(結果.警告件数(), 1, "指摘: {結果}");
}
