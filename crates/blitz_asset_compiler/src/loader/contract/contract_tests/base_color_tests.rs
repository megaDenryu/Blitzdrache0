//! ベースカラーが白のまま焼ける材質の検査の試験。担当するのは、色を与えていない材質を拒むことと、
//! マテリアルを宣言していないプリミティブを対象にしないことの2つを固定することである。
//!
//! 材質スロットの契約の試験と分けているのは、こちらが見るのが「色が与えられているか」という別の問いであり、
//! スロットの数え方や割り当ての契約とは変わる理由が違うためである。

use super::super::fixture_json::{マテリアルなしの三角形, 合格の指定};
use super::検査する;

/// ベースカラーのテクスチャも係数も無い材質は真っ白に焼ける。焼けても作者の宣言と絵が食い違うため違反にする。
#[test]
fn ベースカラーが白のままの材質は違反になる() {
    let mut 指定 = 合格の指定();
    指定.マテリアル列 = 色を与えない材質;
    let 結果 = 検査する("白のままの材質", &指定);
    assert!(!結果.合格か(), "指摘: {結果}");
    assert_eq!(結果.違反件数(), 1, "指摘: {結果}");
}

/// マテリアルを宣言していないプリミティブはこの検査の対象外である。群の原型が材質を持たない形で正当に成立し、
/// 色は`archetype_material`が後から与えるためである。ここが対象になると植生の原型が全件落ちる。
#[test]
fn マテリアルを宣言しないプリミティブは白の検査の対象にならない() {
    let mut 指定 = 合格の指定();
    指定.プリミティブ列 = マテリアルなしの三角形;
    let 結果 = 検査する("宣言なしは白の検査の対象外", &指定);
    assert_eq!(結果.違反件数(), 0, "指摘: {結果}");
}

const 色を与えない材質: &str = r#"{ "doubleSided": true, "pbrMetallicRoughness": { "metallicFactor": 0.5, "roughnessFactor": 0.4 } }"#;
