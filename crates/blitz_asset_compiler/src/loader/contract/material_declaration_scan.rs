//! 材質の割り当て忘れの検査。受け取るのはglTF文書、返すのは指摘一覧である。
//! 由来は`loader::material_slots`がマテリアルの宣言なしも1つの材質スロットとして受け取り、glTFの既定マテリアル(白・金属度1.0・粗さ1.0)で焼くことである。
//!
//! 重大度を宣言の混ざり方で分ける。1つでも宣言したプリミティブがあるのに宣言しないプリミティブが混ざっているなら、
//! 作者が一部の面へ材質を割り当て忘れたことが確定するため違反にする。全プリミティブが宣言していないなら、
//! 材質を持たない素材として書き出された正当な形であり、既定マテリアルで焼かれることを告げる警告にとどめる。
//! 後者は植生の原型がとる形であり、材質はアセットコンパイラが後から与える(参照: `loader/archetype_material.rs`)。

use super::finding::契約指摘;
use super::target::{名前を写す, 対象位置};

pub(super) fn 検査する(文書: &gltf::Document) -> Vec<契約指摘> {
    let Some(メッシュ) = 文書.meshes().next() else {
        return Vec::new();
    };
    let プリミティブ一覧: Vec<gltf::Primitive<'_>> = メッシュ.primitives().collect();
    let 未宣言の添字一覧: Vec<usize> = プリミティブ一覧
        .iter()
        .enumerate()
        .filter(|(_, プリミティブ)| プリミティブ.material().index().is_none())
        .map(|(添字, _)| 添字)
        .collect();

    if 未宣言の添字一覧.is_empty() {
        return Vec::new();
    }
    if 未宣言の添字一覧.len() == プリミティブ一覧.len() {
        return vec![全件が未宣言の警告(&メッシュ)];
    }
    未宣言の添字一覧.into_iter().map(割り当て忘れの違反).collect()
}

/// 他のプリミティブが材質を持つのに自分だけ持たないプリミティブは、面へマテリアルスロットを割り当て忘れた結果である。
/// 既定マテリアルは白・金属度1.0・粗さ1.0であり、作者が他の面へ与えた材質とは似ても似つかない見え方になる。
fn 割り当て忘れの違反(添字: usize) -> 契約指摘 {
    契約指摘::違反を作る(
        対象位置::プリミティブ {
            メッシュ添字: 0, 添字
        },
        "他のプリミティブがマテリアルを宣言しているのにこれだけが宣言していない。glTFの既定マテリアル(白・金属度1.0・粗さ1.0)で焼かれ、作者が他の面へ与えた材質と食い違う",
        "Blenderでこの面へマテリアルを割り当てる。材質を分けたい面はマテリアルスロットを足してから割り当てる",
    )
}

/// 材質を1つも宣言しないメッシュは、色を後から与える素材として正当に成立する。捨てられる宣言が無いため違反にしない。
fn 全件が未宣言の警告(メッシュ: &gltf::Mesh<'_>) -> 契約指摘 {
    契約指摘::警告を作る(
        対象位置::メッシュ {
            添字: 0,
            名前: 名前を写す(メッシュ.name()),
        },
        "マテリアルを1つも宣言していない。glTFの既定マテリアル(白・金属度1.0・粗さ1.0)として焼かれる",
        "作者の色で描きたいなら、Blenderでマテリアルを1つ作って全面へ割り当てる。色を後から与える素材ならこのままでよい",
    )
}
