//! 読めた接合点そのものへの検査。担当するのは、名前が部品の中で一意であることと、位置がメッシュの境界箱の内側にあることである。
//!
//! 読み取りの側から分けているのは、この2つが宣言1件では判定できないためである。名前の重複は他の宣言と突き合わせて初めて分かり、
//! 位置の妥当性はメッシュの幾何と突き合わせて初めて分かる。読み取りは宣言1件を見る工程であり、ここは束を見る工程である。
//!
//! 位置の検査が最も重要である。**接合点の位置は作者がそう宣言した値でしかなく、メッシュの実物と一致している保証がどこにも無い。**
//! 一致を機械で確かめない限り、宣言と実物のずれは誰にも見えない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合点の検査項目」

use super::super::joint::部品の接合点の読み取り;
use super::inspection::開いた文書の契約検査;
use super::mesh_bounds::メッシュの境界箱;
use super::target::対象位置;

impl 開いた文書の契約検査<'_> {
    pub(super) fn 接合点の名前が一意であることを検査する(&mut self, 読み取り: &部品の接合点の読み取り) {
        let 名前一覧: Vec<String> = 読み取り
            .宣言ごとの結果()
            .iter()
            .filter_map(|成否| 成否.読めた接合点())
            .map(|接合点| 接合点.名前().綴り().to_string())
            .collect();
        for (添字, 名前) in 名前一覧.iter().enumerate() {
            if !名前一覧[..添字].contains(名前) {
                continue;
            }
            self.違反を記す(
                対象位置::接合点 {
                    添字,
                    名前: Some(名前.clone()),
                },
                format!("接合点の名前「{名前}」が部品の中で重なっている。組み立て規則が名前で接合点を指すため、指す先が決まらない"),
                "Blender側の接合点の登録で、部品の中で重ならない名前を付ける",
            );
        }
    }

    pub(super) fn 接合点の位置が境界箱の内側にあることを検査する(&mut self, 読み取り: &部品の接合点の読み取り) {
        let Some(メッシュ) = self.文書の全体().meshes().next() else {
            return;
        };
        let Ok(境界箱) = メッシュの境界箱::メッシュのアクセサの宣言から読む(&メッシュ) else {
            return;
        };
        for (添字, 接合点) in 読み取りから接合点を数え上げる(読み取り) {
            let 位置 = 接合点.位置();
            let 成分 = [位置.x().値(), 位置.y().値(), 位置.z().値()];
            if 境界箱.点を含むか(成分) {
                continue;
            }
            self.違反を記す(
                対象位置::接合点 {
                    添字,
                    名前: Some(接合点.名前().綴り().to_string()),
                },
                format!("接合点の位置{成分:?}がメッシュの境界箱の外にある。宣言と実物が食い違っている"),
                "Blender側で接合点の位置をメッシュの境界箱の内側か面上へ置き直す。glTFの座標系(Yが上)へ変換してから載せているかも確かめる",
            );
        }
    }
}

/// 境界箱を読めない事情をここで指摘にしないのは、同じ破れを`geometry_scan`が既に見ており、指摘が二重に並ぶためである。
fn 読み取りから接合点を数え上げる(読み取り: &部品の接合点の読み取り) -> Vec<(usize, &blitz_assembly::接合点)> {
    読み取り
        .宣言ごとの結果()
        .iter()
        .enumerate()
        .filter_map(|(添字, 成否)| 成否.読めた接合点().map(|接合点| (添字, 接合点)))
        .collect()
}
