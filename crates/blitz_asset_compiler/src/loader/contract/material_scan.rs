//! 材質スロットごとのマテリアルをローダーに読ませ、実行時形式が受け取れる値かを判定する。受け取るのは材質スロット一覧である。
//! ローダーに読ませるのは、テクスチャの実体を実際にデコードできるかが契約の本体であり、宣言だけを見ても分からないためである。
//! 由来は`blitz_engine`の実行時形式が金属粗さPBRの係数を0以上1以下に限ることである。
//! 全スロットを見るのは、1メッシュが複数の材質を持てるようになり、先頭以外の材質も同じ実行時形式へ焼かれるためである。
//! テクスチャの幅と高さが1以上であることはローダーが作る`格納済みテクスチャ`の生成が拒むため、破れはマテリアルを読めなかった指摘として出る。
//! 注意: デコードは最初の失敗で止まるため、1つの材質で複数のテクスチャが同時に壊れていても報告は1件になる。宣言側の形式は`texture_scan`が全件見る。

use blitz_engine::金属粗さPBRデータ;

use crate::texture_storage::テクスチャ格納方針;

use super::super::material;
use super::inspection::開いた文書の契約検査;
use super::slot_materials::材質スロットの参照;
use super::target::{名前を写す, 対象位置};

/// 契約検査が読むときに渡す格納方針。この検査が見るのはソースを復号できるかと係数の範囲であり、
/// どの格納形式で焼くかは検査の対象でないため、符号化の要らない非圧縮を選ぶ。
const 契約検査の格納方針: テクスチャ格納方針 = テクスチャ格納方針::全てRGBA8;

impl 開いた文書の契約検査<'_> {
    pub(super) fn 材質スロットごとのマテリアルを検査する(&mut self, 材質スロット一覧: &[材質スロットの参照<'_>]) {
        for スロット in 材質スロット一覧 {
            self.スロットのマテリアルを読んで検査する(スロット);
        }
    }

    fn スロットのマテリアルを読んで検査する(&mut self, スロット: &材質スロットの参照<'_>) {
        let 読込結果 = material::マテリアルを取り出す(self.開いた文書を参照する(), &スロット.プリミティブ, 契約検査の格納方針);
        match 読込結果 {
            Ok((材質, _)) => self.金属粗さの各係数を検査する(スロット.番号, &材質),
            Err(誤り) => self.違反を記す(
                対象位置::マテリアル {
                    スロット: スロット.番号,
                    名前: 名前を写す(スロット.プリミティブ.material().name()),
                },
                format!("マテリアルを読めなかった: {誤り}"),
                "テクスチャをpng形式かjpeg形式にし、glbへ埋め込むか、.gltfと同じディレクトリへ実体を置く",
            ),
        }
    }

    fn 金属粗さの各係数を検査する(&mut self, スロット: u32, 材質: &金属粗さPBRデータ) {
        for (成分名, 値) in 係数一覧(材質) {
            self.係数が0以上1以下の有限値であることを検査する(スロット, 成分名, 値);
        }
    }

    fn 係数が0以上1以下の有限値であることを検査する(&mut self, スロット: u32, 成分名: &str, 値: f32) {
        if 値.is_finite() && (0.0..=1.0).contains(&値) {
            return;
        }
        self.違反を記す(
            対象位置::マテリアル { スロット, 名前: None },
            format!("{成分名}が{値}である。実行時形式は0以上1以下の有限値だけを受け取る"),
            "Blenderのプリンシプル BSDF で、対応する入力値を0から1の範囲へ収める",
        );
    }
}

fn 係数一覧(材質: &金属粗さPBRデータ) -> [(&'static str, f32); 6] {
    [
        ("ベースカラー係数のR", 材質.ベースカラー係数[0]),
        ("ベースカラー係数のG", 材質.ベースカラー係数[1]),
        ("ベースカラー係数のB", 材質.ベースカラー係数[2]),
        ("ベースカラー係数のA", 材質.ベースカラー係数[3]),
        ("金属度係数", 材質.金属度係数),
        ("粗さ係数", 材質.粗さ係数),
    ]
}
