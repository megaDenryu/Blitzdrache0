//! 先頭プリミティブのマテリアルをローダーに読ませ、実行時形式が受け取れる値かを判定する。受け取るのは開いた文書、返すのは指摘一覧である。
//! ローダーに読ませるのは、テクスチャの実体を実際にデコードできるかが契約の本体であり、宣言だけを見ても分からないためである。
//! 由来は`blitz_engine`の実行時形式が金属粗さPBRの係数を0以上1以下に限り、テクスチャの幅と高さを1以上に限ることである。
//! 注意: デコードは最初の失敗で止まるため、複数のテクスチャが同時に壊れていても報告は1件になる。宣言側の形式は`texture_scan`が全件見る。

use blitz_engine::{テクスチャデータ, マテリアルデータ, 金属粗さPBRデータ};

use super::super::document::開いた文書;
use super::super::material;
use super::finding::契約指摘;
use super::target::{名前を写す, 対象位置};

pub(super) fn 検査する(文書: &開いた文書) -> Vec<契約指摘> {
    let Some(プリミティブ) = 文書.document.meshes().next().and_then(|メッシュ| メッシュ.primitives().next()) else {
        return Vec::new();
    };
    let 位置 = 対象位置::マテリアル {
        名前: 名前を写す(プリミティブ.material().name()),
    };

    match material::マテリアルを取り出す(文書, &プリミティブ) {
        Ok((マテリアルデータ::金属粗さPBR(材質), _)) => 材質を検査する(&材質),
        Err(誤り) => vec![契約指摘::違反を作る(
            位置,
            format!("マテリアルを読めなかった: {誤り}"),
            "テクスチャをpng形式かjpeg形式にし、glbへ埋め込むか、.gltfと同じディレクトリへ実体を置く",
        )],
    }
}

fn 材質を検査する(材質: &金属粗さPBRデータ) -> Vec<契約指摘> {
    let mut 指摘一覧 = Vec::new();
    for (成分名, 値) in 係数一覧(材質) {
        係数を検査する(&mut 指摘一覧, 成分名, 値);
    }
    for (用途, テクスチャ) in [
        ("ベースカラー", &材質.ベースカラー),
        ("金属粗さ", &材質.金属粗さ),
        ("法線マップ", &材質.法線マップ),
    ] {
        if let Some(テクスチャ) = テクスチャ {
            寸法を検査する(&mut 指摘一覧, 用途, テクスチャ);
        }
    }
    指摘一覧
}

fn 係数一覧(材質: &金属粗さPBRデータ) -> [(&'static str, f32); 6] {
    [
        ("ベースカラー係数のR", 材質.ベースカラー係数[0]),
        ("ベースカラー係数のG", 材質.ベースカラー係数[1]),
        ("ベースカラー係数のB", 材質.ベースカラー係数[2]),
        ("ベースカラー係数のA", 材質.ベースカラー係数[3]),
        ("金属度係数", 材質.金属度係数),
        ("粗さ係数", 材質.粗さ係数),
    ]
}

fn 係数を検査する(指摘一覧: &mut Vec<契約指摘>, 成分名: &str, 値: f32) {
    if 値.is_finite() && (0.0..=1.0).contains(&値) {
        return;
    }
    指摘一覧.push(契約指摘::違反を作る(
        対象位置::マテリアル { 名前: None },
        format!("{成分名}が{値}である。実行時形式は0以上1以下の有限値だけを受け取る"),
        "Blenderのプリンシプル BSDF で、対応する入力値を0から1の範囲へ収める",
    ));
}

fn 寸法を検査する(指摘一覧: &mut Vec<契約指摘>, 用途: &'static str, テクスチャ: &テクスチャデータ) {
    if テクスチャ.幅 >= 1 && テクスチャ.高さ >= 1 {
        return;
    }
    指摘一覧.push(契約指摘::違反を作る(
        対象位置::テクスチャ { 用途 },
        format!(
            "幅{}高さ{}である。実行時形式は幅と高さが1以上のテクスチャだけを受け取る",
            テクスチャ.幅, テクスチャ.高さ
        ),
        "1画素以上の画像を割り当てる",
    ));
}
