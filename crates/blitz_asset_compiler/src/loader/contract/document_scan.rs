//! 文書ぜんたいの構成の検査。担当するのはメッシュの個数、宣言された拡張機能、カメラの有無であり、メッシュの中身は見ない。
//! 由来は`loader::mod`の`ソースシーンを読み込む`が`document.meshes().next()`だけを読み、拡張機能とカメラを一度も参照しないことである。
//!
//! メッシュの個数の検査と、拡張機能とカメラの検査を別の口にするのは、課す契約が違うためである。前者は1メッシュを
//! 要求する静的シーンだけが課し、後者は静的シーンと部品の両方が課す。部品はメッシュを段の列として読むため、
//! 個数を1に縛れない。

use super::inspection::開いた文書の契約検査;
use super::target::{名前を写す, 対象位置};

impl 開いた文書の契約検査<'_> {
    pub(super) fn 文書の構成を検査する(&mut self) {
        self.メッシュの個数を検査する();
        self.文書の宣言を検査する();
    }

    /// 読まれない宣言の検査。メッシュをどう並べるかに依らないため、静的シーンと部品の両方が課す。
    pub(super) fn 文書の宣言を検査する(&mut self) {
        self.宣言された拡張機能を検査する();
        self.カメラの有無を検査する();
    }

    /// ローダーは先頭メッシュだけを読むため、2個目以降は無言で捨てられる。0個は型付きエラーになる。
    fn メッシュの個数を検査する(&mut self) {
        let メッシュ数 = self.文書の全体().meshes().len();
        if メッシュ数 == 1 {
            return;
        }
        let 是正方法 =
            "1つのglTFへ1つのメッシュだけを入れる。Blenderでは書き出し前にオブジェクトを1つへ結合するか、オブジェクトごとに別のglbへ書き出す";
        self.違反を記す(
            対象位置::文書,
            format!("メッシュが{メッシュ数}個ある。ローダーは先頭のメッシュだけを読み、残りを無言で捨てる"),
            是正方法,
        );
        for (添字, メッシュ) in self.文書の全体().meshes().enumerate().skip(1) {
            self.違反を記す(
                対象位置::メッシュ {
                    添字,
                    名前: 名前を写す(メッシュ.name()),
                },
                "先頭でないメッシュのため読まれない",
                是正方法,
            );
        }
    }

    /// ローダーは拡張機能を一度も解釈しない。必須宣言は絵が確実に食い違い、使用宣言は捨てられる。
    fn 宣言された拡張機能を検査する(&mut self) {
        for 拡張名 in self.文書の全体().extensions_required() {
            self.違反を記す(
                対象位置::文書,
                format!("読み込みに必須の拡張機能{拡張名}が宣言されている。ローダーは拡張機能を解釈しない"),
                "Blenderの書き出し設定でその拡張機能を切り、標準のpbrMetallicRoughnessだけで材質を表す",
            );
        }
        for 拡張名 in self.文書の全体().extensions_used() {
            self.警告を記す(
                対象位置::文書,
                format!("拡張機能{拡張名}を使う宣言がある。ローダーは読まないため、この拡張で足した情報は絵に出ない"),
                "その拡張で表していた見た目を標準のpbrMetallicRoughnessへ移すか、絵に出ないことを受け入れる",
            );
        }
    }

    /// ローダーはカメラを読まない。視点はシーン名からアプリ側が決める。
    fn カメラの有無を検査する(&mut self) {
        let カメラ数 = self.文書の全体().cameras().len();
        if カメラ数 == 0 {
            return;
        }
        self.警告を記す(
            対象位置::文書,
            format!("カメラが{カメラ数}個含まれる。ローダーは読まず、視点はアプリ側がシーン名から決める"),
            "Blenderの書き出し設定でカメラを除く",
        );
    }
}
