//! 文書ぜんたいの構成の検査。担当するのはメッシュの個数、宣言された拡張機能、カメラの有無であり、メッシュの中身は見ない。
//! 由来は`loader::mod`の`ソースシーンを読み込む`が`document.meshes().next()`だけを読み、拡張機能とカメラを一度も参照しないことである。

use super::finding::契約指摘;
use super::target::{名前を写す, 対象位置};

pub(super) fn 検査する(文書: &gltf::Document) -> Vec<契約指摘> {
    let mut 指摘一覧 = Vec::new();
    メッシュ数を検査する(文書, &mut 指摘一覧);
    拡張機能を検査する(文書, &mut 指摘一覧);
    カメラを検査する(文書, &mut 指摘一覧);
    指摘一覧
}

/// ローダーは先頭メッシュだけを読むため、2個目以降は無言で捨てられる。0個は型付きエラーになる。
fn メッシュ数を検査する(文書: &gltf::Document, 指摘一覧: &mut Vec<契約指摘>) {
    let メッシュ数 = 文書.meshes().len();
    if メッシュ数 == 1 {
        return;
    }
    let 是正方法 = "1つのglTFへ1つのメッシュだけを入れる。Blenderでは書き出し前にオブジェクトを1つへ結合するか、オブジェクトごとに別のglbへ書き出す";
    指摘一覧.push(契約指摘::違反を作る(
        対象位置::文書,
        format!("メッシュが{メッシュ数}個ある。ローダーは先頭のメッシュだけを読み、残りを無言で捨てる"),
        是正方法,
    ));
    for (添字, メッシュ) in 文書.meshes().enumerate().skip(1) {
        指摘一覧.push(契約指摘::違反を作る(
            対象位置::メッシュ {
                添字,
                名前: 名前を写す(メッシュ.name()),
            },
            "先頭でないメッシュのため読まれない",
            是正方法,
        ));
    }
}

/// ローダーは拡張機能を一度も解釈しない。必須宣言は絵が確実に食い違い、使用宣言は捨てられる。
fn 拡張機能を検査する(文書: &gltf::Document, 指摘一覧: &mut Vec<契約指摘>) {
    for 拡張名 in 文書.extensions_required() {
        指摘一覧.push(契約指摘::違反を作る(
            対象位置::文書,
            format!("読み込みに必須の拡張機能{拡張名}が宣言されている。ローダーは拡張機能を解釈しない"),
            "Blenderの書き出し設定でその拡張機能を切り、標準のpbrMetallicRoughnessだけで材質を表す",
        ));
    }
    for 拡張名 in 文書.extensions_used() {
        指摘一覧.push(契約指摘::警告を作る(
            対象位置::文書,
            format!("拡張機能{拡張名}を使う宣言がある。ローダーは読まないため、この拡張で足した情報は絵に出ない"),
            "その拡張で表していた見た目を標準のpbrMetallicRoughnessへ移すか、絵に出ないことを受け入れる",
        ));
    }
}

/// ローダーはカメラを読まない。視点はシーン名からアプリ側が決める。
fn カメラを検査する(文書: &gltf::Document, 指摘一覧: &mut Vec<契約指摘>) {
    let カメラ数 = 文書.cameras().len();
    if カメラ数 == 0 {
        return;
    }
    指摘一覧.push(契約指摘::警告を作る(
        対象位置::文書,
        format!("カメラが{カメラ数}個含まれる。ローダーは読まず、視点はアプリ側がシーン名から決める"),
        "Blenderの書き出し設定でカメラを除く",
    ));
}
