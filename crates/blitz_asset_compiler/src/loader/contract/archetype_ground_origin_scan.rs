//! 全段の原点が接地面の中央にあることの検査。担当するのは段の境界箱を原点と突き合わせることと、破れの文面である。
//! 箱を読む手順は`archetype_bounds`が持つ。
//!
//! 由来は散布が個体を地表の点へ平行移動と天頂軸まわりの回転だけで置くことである。原型の原点が接地面の中央から外れていると、
//! 全個体が地面から浮くか埋まるかし、向きを変えると原点のまわりで振り回されて立つ位置が動く。段ごとに原点が違えば、段の切替の瞬間に個体が飛ぶ。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「個体別LOD」

use super::archetype_bounds::{境界箱を読めない理由, 段の境界箱};
use super::inspection::開いた文書の契約検査;
use super::target::{名前を写す, 対象位置};

/// 原点に乗っていることを見る3つの成分。glTFはY軸を上とするため、接地は底面の高さ、中央は水平2軸の中心で表れる。
enum 原点に乗ることを見る成分 {
    底面の高さ,
    X軸方向の中心,
    Z軸方向の中心,
}

impl 原点に乗ることを見る成分 {
    fn 箱から原点からのずれを読む(&self, 箱: &段の境界箱) -> f32 {
        match self {
            Self::底面の高さ => 箱.底面の高さ(),
            Self::X軸方向の中心 => 箱.x軸方向の中心の原点からのずれ(),
            Self::Z軸方向の中心 => 箱.z軸方向の中心の原点からのずれ(),
        }
    }

    fn 指摘に書く名(&self) -> &'static str {
        match self {
            Self::底面の高さ => "底面の高さ",
            Self::X軸方向の中心 => "X軸方向の中心",
            Self::Z軸方向の中心 => "Z軸方向の中心",
        }
    }
}

impl 開いた文書の契約検査<'_> {
    pub(super) fn 全段の原点が接地面の中央にあることを検査する(&mut self) {
        for (段番号, メッシュ) in self.文書の全体().meshes().enumerate() {
            match 段の境界箱::メッシュのアクセサの宣言から読む(&メッシュ) {
                Ok(箱) => self.段の箱が原点に乗ることを検査する(段番号, &箱),
                Err(理由) => self.境界箱を読めない違反を記す(段番号, &メッシュ, &理由),
            }
        }
    }

    /// 許容差は箱の大きさから決まるため段ごとに違う。3つの成分を別々の指摘にするのは、直す向きが成分ごとに違うためである。
    fn 段の箱が原点に乗ることを検査する(&mut self, 段番号: usize, 箱: &段の境界箱) {
        let 許容差 = 箱.原点からのずれの許容差();
        let 見る成分一覧 = [
            原点に乗ることを見る成分::底面の高さ,
            原点に乗ることを見る成分::X軸方向の中心,
            原点に乗ることを見る成分::Z軸方向の中心,
        ];
        for 成分 in 見る成分一覧 {
            let ずれ = 成分.箱から原点からのずれを読む(箱);
            if ずれ.abs() > 許容差 {
                self.原点からのずれの違反を記す(段番号, &成分, ずれ, 許容差);
            }
        }
    }

    fn 原点からのずれの違反を記す(
        &mut self, 段番号: usize, 成分: &原点に乗ることを見る成分, ずれ: f32, 許容差: f32
    ) {
        let 成分の名 = 成分.指摘に書く名();
        self.違反を記す(
            対象位置::メッシュ { 添字: 段番号, 名前: None },
            format!("段{段番号}の{成分の名}が原点から{ずれ}ずれている(許容差{許容差})。散布は個体を地表の点へ置いて天頂軸まわりに回すため、原型の原点は接地面の中央でなければならない"),
            "Blenderで原点を底面の中央へ移してから書き出す(3Dカーソルを原点へ置き、原点を3Dカーソルへ設定する)。全ての段の原点を揃える",
        );
    }

    fn 境界箱を読めない違反を記す(&mut self, 段番号: usize, メッシュ: &gltf::Mesh<'_>, 理由: &境界箱を読めない理由) {
        let 事情 = match 理由 {
            境界箱を読めない理由::プリミティブが1つも無い => "プリミティブが1つも無い",
            境界箱を読めない理由::頂点位置の属性が無い => "頂点位置(POSITION)の属性が無い",
            境界箱を読めない理由::頂点位置の最小か最大の宣言が無い => {
                "頂点位置のアクセサに最小(min)か最大(max)の宣言が無い"
            }
            境界箱を読めない理由::頂点位置の最小か最大を3つの小数として読めない => {
                "頂点位置の最小と最大が3つの小数の並びになっていない"
            }
        };
        self.違反を記す(
            対象位置::メッシュ {
                添字: 段番号,
                名前: 名前を写す(メッシュ.name()),
            },
            format!("段{段番号}の境界箱を読めない: {事情}"),
            "Blenderの書き出し設定で頂点位置を含め、アクセサの最小と最大が付いた三角形メッシュとして書き出す",
        );
    }
}
