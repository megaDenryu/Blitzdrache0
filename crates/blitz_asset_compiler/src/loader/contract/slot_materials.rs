//! ローダーが読むメッシュが参照するマテリアルを、材質スロットの並びで数え上げる工程。受け取るのは契約とglTF文書、
//! 返すのはスロット番号と参照元プリミティブの組の一覧である。
//! 同じマテリアルを参照するプリミティブを1件へ畳むのは、`loader::material_slots::解決する`がスロットごとに材質を1回だけ読み、
//! 実行時形式もスロット単位で材質を持つためである。指摘の粒度を焼く単位と揃えると、同じ破れが参照回数ぶん並ばない。
//! プリミティブを添えて返すのは、`loader::material::マテリアルを取り出す`がマテリアルをプリミティブ越しに読むためである。
//! 番号の振り方を写しで持たず`材質スロット語彙`へ委ねるのは、検査が報告するスロット番号を実行時形式のスロット番号と一致させるためである。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「入力契約と実行時形式(scene v4、実装済み)」

use super::super::material_slots::材質スロット語彙;
use super::inspected_contract::検査する契約;

/// 材質スロット1つと、そのスロットを最初に参照したプリミティブ。
pub(super) struct 材質スロットの参照<'文書> {
    pub(super) 番号: u32,
    pub(super) プリミティブ: gltf::Primitive<'文書>,
}

impl<'文書> 材質スロットの参照<'文書> {
    /// その契約でローダーが実際に読むメッシュから数え上げる。静的シーンは先頭メッシュだけを読むため、
    /// 2つ目以降のメッシュの材質を数えると、焼かれないものへ指摘が出る。段の列を読む2つの契約は全段が焼かれる。
    pub(super) fn ローダーが読むメッシュの材質スロットを数え上げる(
        契約: 検査する契約,
        文書: &'文書 gltf::Document,
    ) -> Vec<Self> {
        let メッシュ一覧: Vec<gltf::Mesh<'文書>> = match 契約 {
            検査する契約::静的シーン => 文書.meshes().take(1).collect(),
            検査する契約::群の原型 | 検査する契約::部品 => 文書.meshes().collect(),
        };
        let 語彙 = 材質スロット語彙::メッシュ列から作る(&メッシュ一覧);
        let mut 一覧: Vec<Self> = Vec::new();
        for プリミティブ in メッシュ一覧.iter().flat_map(gltf::Mesh::primitives) {
            let Some(番号) = 語彙.スロットを参照する(&プリミティブ).map(blitz_engine::材質スロットID::番号を返す)
            else {
                continue;
            };
            if 一覧.iter().any(|登録済み| 登録済み.番号 == 番号) {
                continue;
            }
            一覧.push(Self { 番号, プリミティブ });
        }
        一覧
    }
}
