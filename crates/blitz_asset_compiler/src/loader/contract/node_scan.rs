//! ノード階層の検査。担当するのは先頭メッシュを参照するノードの個数と、そのノードから根までの変換であり、メッシュの中身は見ない。
//! 由来は`loader::mod`の`ソースシーンを読み込む`が配置変換に単位行列を直接与え、glTFのノード変換とシーングラフを一度も読まないことである。
//! スキン付きのメッシュを除くのは、スキン付きメッシュのノード変換はglTFの仕様が無視を要求するため、捨てられても食い違いにならないからである。
//! 根まで遡る手順そのものは`node_transform`が持ち、ここは何が破れかと文面だけを持つ。

use super::inspection::開いた文書の契約検査;
use super::node_transform::ノードの親子関係の索引;
use super::target::対象位置;

impl 開いた文書の契約検査<'_> {
    pub(super) fn ノード階層を検査する(&mut self) {
        let 索引 = ノードの親子関係の索引::文書から作る(self.文書の全体());
        let 参照ノード一覧: Vec<gltf::Node<'_>> = self
            .文書の全体()
            .nodes()
            .filter(|ノード| ノード.mesh().is_some_and(|メッシュ| メッシュ.index() == 0))
            .collect();

        self.先頭メッシュを参照するノードの個数を検査する(参照ノード一覧.len());
        for ノード in 参照ノード一覧.iter().filter(|ノード| ノード.skin().is_none()) {
            self.先頭メッシュに効く変換を検査する(&索引, ノード);
        }
    }

    fn 先頭メッシュを参照するノードの個数を検査する(&mut self, 参照数: usize) {
        if 参照数 == 1 {
            return;
        }
        self.違反を記す(
            対象位置::文書,
            format!("先頭メッシュを参照するノードが{参照数}個ある。ローダーはメッシュを1回だけ読み、ノードごとの配置を作らない"),
            "1つのメッシュを1つのノードだけが参照する形にする。Blenderで同じメッシュを共有する複製(リンク複製)を使っているなら、実体化して別メッシュにするか複製を消す",
        );
    }

    /// ノード自身と、根まで遡った祖先の変換を見る。1つでも単位行列でなければ、その分だけ絵が宣言とずれる。
    fn 先頭メッシュに効く変換を検査する(&mut self, 索引: &ノードの親子関係の索引, ノード: &gltf::Node<'_>) {
        for 位置 in 索引.根まで遡って変換を持つノードを集める(self.文書の全体(), ノード) {
            self.違反を記す(
                位置,
                "先頭メッシュに効くノード変換が単位行列でない。ローダーは配置変換に単位行列を与えるため、この平行移動・回転・拡大縮小は無言で捨てられる",
                "Blenderで対象と親の変換をメッシュ実体へ適用してから書き出す(オブジェクトモードで全トランスフォーム適用)。配置はエンジン側のシーン定義で与える",
            );
        }
    }
}
