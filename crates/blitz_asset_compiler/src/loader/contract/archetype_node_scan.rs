//! 群の原型のノードの検査。担当するのはノードの数が段の数と揃っていることと、段に効く変換が単位行列であることである。
//! 由来は`loader::archetype`が文書のメッシュを段番号順に読むだけでノードを一度も見ないことである。
//! ノードが段と1対1でなければ、Blender側のどのオブジェクトがどの段なのかを読み手が対応付けられず、変換は読まれずに捨てられる。
//! 根まで遡る手順そのものは`node_transform`が持つ。

use super::inspection::開いた文書の契約検査;
use super::node_transform::ノードの親子関係の索引;
use super::target::対象位置;

impl 開いた文書の契約検査<'_> {
    pub(super) fn 段ごとのノードを検査する(&mut self) {
        self.ノードの数が段の数と一致することを検査する();
        let 索引 = ノードの親子関係の索引::文書から作る(self.文書の全体());
        let 段を参照するノード一覧: Vec<gltf::Node<'_>> = self.文書の全体().nodes().filter(|ノード| ノード.mesh().is_some()).collect();
        for ノード in &段を参照するノード一覧 {
            self.段に効く変換を検査する(&索引, ノード);
        }
    }

    fn ノードの数が段の数と一致することを検査する(&mut self) {
        let 段数 = self.文書の全体().meshes().len();
        let ノード数 = self.文書の全体().nodes().len();
        if ノード数 == 段数 {
            return;
        }
        self.違反を記す(
            対象位置::文書,
            format!("ノードが{ノード数}個、段(メッシュ)が{段数}個で数が一致しない。段とノードが1対1でないと、どのノードがどの段なのかを読み手が対応付けられない"),
            "1つの段を1つのノードだけが参照する形にする。Blenderで段ごとに1つのオブジェクトを置き、空オブジェクトやカメラなどメッシュを持たないオブジェクトを書き出しに含めない",
        );
    }

    /// 原型の個体は散布が与える配置変換で置かれ、ノード変換は読まれない。単位行列でなければその分だけ絵が宣言とずれる。
    fn 段に効く変換を検査する(&mut self, 索引: &ノードの親子関係の索引, ノード: &gltf::Node<'_>) {
        for 位置 in 索引.根まで遡って変換を持つノードを集める(self.文書の全体(), ノード) {
            self.違反を記す(
                位置,
                "段に効くノード変換が単位行列でない。原型の読み取りはノードを見ず、個体の配置は散布が与えるため、この平行移動・回転・拡大縮小は無言で捨てられる",
                "Blenderで対象と親の変換をメッシュ実体へ適用してから書き出す(オブジェクトモードで全トランスフォーム適用)。段どうしは同じ原点に重ねて置く",
            );
        }
    }
}
