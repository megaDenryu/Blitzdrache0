//! 検査結果の報告文。担当するのは1回の検査を1つの読み物へ組み立てることであり、判定は`result`が持つ。
//! 概要を先に置き指摘を後に置くのは、読む側が最初に「何を検査したか」を確かめてから破れを読むためである。
//! 幾何の数値に先頭のメッシュだけを読んだと書き添えるのは、群の原型では段の数だけメッシュが並び、どの段を計った数なのかが数字だけでは決まらないためである。

use std::fmt;

use super::result::{契約検査概要, 契約検査結果};

impl fmt::Display for 契約検査結果 {
    fn fmt(&self, 出力: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.概要() {
            Some(概要) => writeln!(出力, "{概要}")?,
            None => writeln!(出力, "概要: 文書を読めなかったため計測していない")?,
        }
        for 指摘 in self.指摘一覧() {
            writeln!(出力, "{指摘}")?;
        }
        write!(
            出力,
            "判定: {} (違反{}件, 警告{}件)",
            判定名(self.合格か()),
            self.違反件数(),
            self.警告件数()
        )
    }
}

fn 判定名(合格か: bool) -> &'static str {
    if 合格か { "合格" } else { "不合格" }
}

impl fmt::Display for 契約検査概要 {
    fn fmt(&self, 出力: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(
            出力,
            "概要: メッシュ{}個, 先頭のメッシュ(群の原型なら最詳細段)のプリミティブ{}個, 材質スロット{}個, 頂点{}個, インデックス{}個",
            self.メッシュ数, self.プリミティブ数, self.材質スロット数, self.頂点数, self.インデックス数
        )?;
        match self.境界箱 {
            Some((最小, 最大)) => write!(
                出力,
                "      先頭のメッシュの境界箱: 最小[{:.3}, {:.3}, {:.3}] 最大[{:.3}, {:.3}, {:.3}]",
                最小[0], 最小[1], 最小[2], 最大[0], 最大[1], 最大[2]
            ),
            None => write!(出力, "      先頭のメッシュの境界箱: 頂点を読めなかったため無し"),
        }
    }
}
