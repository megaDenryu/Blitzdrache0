//! 群の原型の契約の走査。担当するのは原型だけに課す項目を呼ぶ順序と、文書が段の列になっていることの検査である。
//! 個々の項目が何を破れとするかは項目ごとのファイルが持つ。
//! 由来は`loader::archetype`の`原型ソースを読み込む`が、文書の並べたメッシュをそのまま詳細段(LOD)の列として読み、先頭を最詳細段とすることである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「個体別LOD」

use super::inspection::開いた文書の契約検査;
use super::target::対象位置;

impl 開いた文書の契約検査<'_> {
    pub(super) fn 群の原型の項目を走査する(&mut self) {
        self.段の列になっていることを検査する();
        self.段ごとのノードを検査する();
        self.段ごとのプリミティブを検査する();
        self.段の間で描画条件が揃うことを検査する();
        self.三角形数が段の順に減ることを検査する();
        self.全段の原点が接地面の中央にあることを検査する();
    }

    /// 原型は段の列であり、メッシュ1個の文書は段の列になっていない。焼いても切り替える先の段が無く、群として遠景で軽くならない。
    fn 段の列になっていることを検査する(&mut self) {
        let メッシュ数 = self.文書の全体().meshes().len();
        if メッシュ数 >= 2 {
            return;
        }
        self.違反を記す(
            対象位置::文書,
            format!("メッシュが{メッシュ数}個しか無い。群の原型は詳細段(LOD)の列であり、段の数だけメッシュを並べる"),
            "遠景用に面を減らした段を作り、詳細な順に並べて1つのglbへ書き出す。段を持たない単体の小物なら、この検査を原型の契約で走らせないで静的シーンの契約で検査する",
        );
    }
}
