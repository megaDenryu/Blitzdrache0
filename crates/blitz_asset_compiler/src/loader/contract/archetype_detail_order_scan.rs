//! 段の並びが詳細な順であることの検査。担当するのは段ごとの三角形数を数えることと、その数が段の順に減っていることである。
//! 由来は`loader::archetype`が文書の並べた順をそのまま段番号とし、先頭を最詳細段として扱うことである。
//! 先頭が最詳細段であることは形の上の宣言でしか表せないため、三角形数が段の順に減っていることを機械の証拠として課す。
//! 後の段が前の段と同じか多ければ、遠景で軽くなるどころか重くなり、段を切り替える意味が失われる。

use super::inspection::開いた文書の契約検査;
use super::target::対象位置;

/// 1つの三角形が使うインデックスの個数。ローダーがインデックス列を三角形リストとして渡すことから決まる。
const 三角形1つぶんのインデックス数: usize = 3;

impl 開いた文書の契約検査<'_> {
    pub(super) fn 三角形数が段の順に減ることを検査する(&mut self) {
        let mut 直前の段: Option<(usize, usize)> = None;
        for (段番号, メッシュ) in self.文書の全体().meshes().enumerate() {
            let 三角形数 = self.段の三角形数を数える(段番号, &メッシュ);
            if let (Some((直前の段番号, 直前の三角形数)), Some(数)) = (直前の段, 三角形数) {
                self.段が前より詳細でないことを検査する(直前の段番号, 直前の三角形数, 段番号, 数);
            }
            直前の段 = 三角形数.map(|数| (段番号, 数));
        }
    }

    /// インデックスの要素数から三角形の数を求める。インデックスを持たない段は違反にして数を返さず、その段を並びの比較から外す。
    fn 段の三角形数を数える(&mut self, 段番号: usize, メッシュ: &gltf::Mesh<'_>) -> Option<usize> {
        let mut 合計 = 0;
        for (添字, プリミティブ) in メッシュ.primitives().enumerate() {
            let Some(インデックス) = プリミティブ.indices() else {
                self.インデックスを持たない段の違反を記す(段番号, 添字);
                return None;
            };
            合計 += インデックス.count() / 三角形1つぶんのインデックス数;
        }
        Some(合計)
    }

    fn インデックスを持たない段の違反を記す(&mut self, 段番号: usize, 添字: usize) {
        self.違反を記す(
            対象位置::プリミティブ {
                メッシュ添字: 段番号, 添字
            },
            format!("段{段番号}のプリミティブがインデックスを持たない。段の詳しさを三角形の数で比べられず、実行時形式もインデックス列を要求する"),
            "Blenderの書き出し設定でインデックスを持つ三角形メッシュとして書き出す",
        );
    }

    fn 段が前より詳細でないことを検査する(
        &mut self, 直前の段番号: usize, 直前の三角形数: usize, 段番号: usize, 三角形数: usize
    ) {
        if 三角形数 < 直前の三角形数 {
            return;
        }
        self.違反を記す(
            対象位置::メッシュ { 添字: 段番号, 名前: None },
            format!("段{段番号}の三角形が{三角形数}個で、段{直前の段番号}の{直前の三角形数}個より減っていない。段は先頭が最詳細で、後の段ほど粗くなる順に並べる"),
            "Blenderで段の並び順を詳細な順へ直すか、後の段の面をさらに減らしてから書き出す",
        );
    }
}
