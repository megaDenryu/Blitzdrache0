//! 部品の契約の走査。担当するのは部品だけに課す項目を呼ぶ順序と、部品に固有の2つの検査である。
//! 個々の項目が何を破れとするかは項目ごとのファイルが持ち、段の列としての項目は群の原型の走査と共有する。
//!
//! 由来は`loader::part_archetype`の`部品の原型ソースを読み込む`が、文書の並べたメッシュを詳細段の列として読み、
//! 材質スロットの語彙を全段のプリミティブから作ることである。段を1つしか持たない部品は、その1つが最詳細段になる。
//!
//! **群の原型と課すものが2つ違う。** 段ごとのプリミティブを1個に縛らないのは、部品が材質スロットの数だけ
//! プリミティブへ分かれるためである。段の間でマテリアルが揃うことを課さないのは、遠距離段が近距離段の材質の
//! 一部だけを使う形も、まとめた1つの材質へ置き換える形も、どちらも正当な簡略化だからである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「段(詳細段)は部品の側へ持たせる」

use super::super::joint::部品の接合点の読み取り;
use super::inspection::開いた文書の契約検査;
use super::target::{名前を写す, 対象位置};

impl 開いた文書の契約検査<'_> {
    pub(super) fn 部品の項目を走査する(&mut self) {
        self.段が1つ以上あることを検査する();
        self.文書の宣言を検査する();
        self.段ごとのノードを検査する();
        self.部品の段ごとのプリミティブを検査する();
        self.三角形数が段の順に減ることを検査する();
        self.接合点の宣言を検査する();
        self.段0以外が接合点を宣言していないことを検査する();
    }

    /// メッシュを1つも持たない文書は段を1つも持たず、原型として焼けない。読み取りが型付きエラーで拒む地点である。
    fn 段が1つ以上あることを検査する(&mut self) {
        if self.文書の全体().meshes().next().is_some() {
            return;
        }
        self.違反を記す(
            対象位置::文書,
            "メッシュが1つも無い。部品はメッシュを詳細段の列として読むため、少なくとも最詳細段の1つが要る",
            "Blenderで面を持つオブジェクトを1つ以上書き出しに含める",
        );
    }

    /// 段のプリミティブが0個だと、その段は面を1つも持たない。個数の上限を置かないのは、部品が材質スロットの数だけ
    /// プリミティブへ分かれるためである。並び方の検査は群の原型と同じものを段ごとに走らせる。
    fn 部品の段ごとのプリミティブを検査する(&mut self) {
        for (段番号, メッシュ) in self.文書の全体().meshes().enumerate() {
            if メッシュ.primitives().next().is_none() {
                self.違反を記す(
                    対象位置::メッシュ {
                        添字: 段番号,
                        名前: 名前を写す(メッシュ.name()),
                    },
                    format!("段{段番号}がプリミティブを1つも持たない。面を持たない段は絵に何も出さない"),
                    "面を持たないオブジェクトを書き出しに含めない。段を減らすなら、そのオブジェクト自体を書き出しから外す",
                );
            }
            for (添字, プリミティブ) in メッシュ.primitives().enumerate() {
                self.段の描画の並び方を検査する(段番号, 添字, &プリミティブ);
            }
        }
    }

    /// 接合点を読むのは段0のノードだけである。段1以降のノードが宣言しても読み取りは一度も見ず、無言で捨てられる。
    /// 段ごとに違う接合点を宣言できると、どの段の宣言が正なのかが決まらない。
    fn 段0以外が接合点を宣言していないことを検査する(&mut self) {
        for ノード in self.文書の全体().nodes() {
            let Some(メッシュ) = ノード.mesh() else { continue };
            if メッシュ.index() == 0 {
                continue;
            }
            let 件数 = match 部品の接合点の読み取り::ノードから読み取る(&ノード) {
                Ok(読み取り) => 読み取り.宣言の件数(),
                Err(_誤り) => 1,
            };
            if 件数 == 0 {
                continue;
            }
            self.違反を記す(
                対象位置::メッシュ {
                    添字: メッシュ.index(),
                    名前: 名前を写す(メッシュ.name()),
                },
                format!(
                    "段{}のノードが接合点を宣言している。接合点を読むのは段0のノードだけであり、この宣言は無言で捨てられる",
                    メッシュ.index()
                ),
                "接合点のカスタムプロパティを最詳細段のオブジェクトだけに付け、遠距離段のオブジェクトからは外す",
            );
        }
    }
}
