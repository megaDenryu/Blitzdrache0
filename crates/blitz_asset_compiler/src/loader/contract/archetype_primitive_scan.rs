//! 群の原型の段ごとのプリミティブの検査。担当するのは段が持つプリミティブの個数と、その描画の並び方(mode)である。
//! 由来は`loader::archetype`が段ごとに`メッシュデータを取り出す`を1回呼び、段の中の全プリミティブを1つの頂点列へ連結することである。
//! 段のプリミティブが2つ以上あると、その段だけ材質の境界が増えて他の段と絵の分かれ方が変わる。
//! 並び方は静的シーンと同じくインデックス列を三角形リストとして渡すため、三角形以外は絵が崩れる。

use super::inspection::開いた文書の契約検査;
use super::target::{名前を写す, 対象位置};

impl 開いた文書の契約検査<'_> {
    pub(super) fn 段ごとのプリミティブを検査する(&mut self) {
        for (段番号, メッシュ) in self.文書の全体().meshes().enumerate() {
            self.段のプリミティブの個数を検査する(段番号, &メッシュ);
            for (添字, プリミティブ) in メッシュ.primitives().enumerate() {
                self.段の描画の並び方を検査する(段番号, 添字, &プリミティブ);
            }
        }
    }

    fn 段のプリミティブの個数を検査する(&mut self, 段番号: usize, メッシュ: &gltf::Mesh<'_>) {
        let プリミティブ数 = メッシュ.primitives().len();
        if プリミティブ数 == 1 {
            return;
        }
        self.違反を記す(
            対象位置::メッシュ {
                添字: 段番号,
                名前: 名前を写す(メッシュ.name()),
            },
            format!("段{段番号}のプリミティブが{プリミティブ数}個ある。原型の段は1つの形を1つのプリミティブで持つ"),
            "Blenderで段ごとに1つのマテリアルだけを割り当て、面が2つ以上のマテリアルに分かれていないかを確かめる。面を持たない段を書き出していないかも確かめる",
        );
    }

    fn 段の描画の並び方を検査する(&mut self, 段番号: usize, 添字: usize, プリミティブ: &gltf::Primitive<'_>) {
        if プリミティブ.mode() == gltf::mesh::Mode::Triangles {
            return;
        }
        self.違反を記す(
            対象位置::プリミティブ {
                メッシュ添字: 段番号, 添字
            },
            format!(
                "段{段番号}の描画の並び方が{:?}である。ローダーはインデックス列を三角形リストとして渡す",
                プリミティブ.mode()
            ),
            "三角形として書き出す。Blenderの書き出し設定で三角形化を有効にし、線や点のオブジェクトを含めない",
        );
    }
}
