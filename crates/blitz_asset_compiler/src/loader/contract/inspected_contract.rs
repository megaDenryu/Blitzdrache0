//! 検査する契約: エンジンがそのglTFをどちらの読み方で受け取るかの選択。担当するのは選択の枝の定義と、
//! プロセスの引数でその選択を運ぶ綴りである。契約ごとに何を課すかは走査の工程が持つ。
//!
//! メッシュの個数から契約を推し量らず、呼び出し側に明示させる。静的シーンとして書き出した小物が誤って
//! 2メッシュになったとき、推し量る形だと原型の契約が無言で当たって合格が返るためである。
//! 契約を取り違えた合格は、検査していないことより悪い。
//!
//! 綴りをこのライブラリが1つ持つのは、xtaskと検査器の2つの実行ファイルが同じ語を使うためである。
//! 選択を綴りの有無で表すため、綴りが片方だけずれると知らない引数として黙って落ち、原型を静的シーンの
//! 契約で検査した結果が返る。綴りの出どころを1つにすることでその食い違いを断つ。

/// エンジンがこのglTFを読む契約。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 検査する契約 {
    静的シーン, // 1ファイルに1メッシュを置く形。`ソースシーンを読み込む`が読む
    群の原型,   // 複数のメッシュを詳細段の列として並べた形。`原型ソースを読み込む`が読む
    部品,       // 静的シーンと同じ形のメッシュへ接合点の宣言の項目を足したもの
}

/// 群の原型を選ぶ綴り。値を続けず、在ることがその契約を意味する。
const 群の原型の綴り: &str = "--archetype";

/// 部品を選ぶ綴り。両方が並んだときは部品を採る。取り違えた合格を返すより、後から書いた指定を採るほうが読み手の意図に近い。
const 部品の綴り: &str = "--part";

impl 検査する契約 {
    /// 引数の並びからこの選択を取り除き、選択と残りの引数を返す。どの綴りも無ければ静的シーンである。
    pub fn 引数一覧から取り出す(引数一覧: &[String]) -> (Self, Vec<String>) {
        let 選択 = if 引数一覧.iter().any(|引数| 引数 == 部品の綴り) {
            Self::部品
        } else if 引数一覧.iter().any(|引数| 引数 == 群の原型の綴り) {
            Self::群の原型
        } else {
            Self::静的シーン
        };
        let 残り = 引数一覧
            .iter()
            .filter(|引数| 引数.as_str() != 群の原型の綴り && 引数.as_str() != 部品の綴り)
            .cloned()
            .collect();
        (選択, 残り)
    }

    /// 検査させる側が引数の並びへ足す綴り。静的シーンのときは1語も足さない。
    pub fn 引数へ足す綴り(self) -> Option<&'static str> {
        match self {
            Self::群の原型 => Some(群の原型の綴り),
            Self::部品 => Some(部品の綴り),
            Self::静的シーン => None,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::検査する契約;

    /// 検査させる側が足した綴りを、検査する側がそのまま読み戻せる。2つの実行ファイルの受け渡しがこの往復に依る。
    #[test]
    fn 足した綴りを読み戻すと同じ選択になる() {
        for 選択 in [検査する契約::静的シーン, 検査する契約::群の原型, 検査する契約::部品] {
            let mut 引数一覧 = vec!["一体目.glb".to_string(), "二体目.glb".to_string()];
            引数一覧.extend(選択.引数へ足す綴り().map(str::to_string));
            let (読んだ, 残り) = 検査する契約::引数一覧から取り出す(&引数一覧);
            assert_eq!(読んだ, 選択);
            assert_eq!(残り, vec!["一体目.glb".to_string(), "二体目.glb".to_string()]);
        }
    }

    /// 2つの綴りが並んだときは部品を採る。取り違えた合格を返すより、後から足された指定を採るほうが読み手の意図に近い。
    #[test]
    fn 両方の綴りが並べば部品を採る() {
        let 引数一覧 = vec!["--archetype".to_string(), "--part".to_string(), "部品.glb".to_string()];
        let (読んだ, 残り) = 検査する契約::引数一覧から取り出す(&引数一覧);
        assert_eq!(読んだ, 検査する契約::部品);
        assert_eq!(残り, vec!["部品.glb".to_string()]);
    }

    /// 綴りが無い引数の並びは静的シーンである。既定が変わると、既存の小物の検査結果が黙って変わる。
    #[test]
    fn 綴りが無ければ静的シーンになる() {
        let (読んだ, _) = 検査する契約::引数一覧から取り出す(&["小物.glb".to_string()]);
        assert_eq!(読んだ, 検査する契約::静的シーン);
    }
}
