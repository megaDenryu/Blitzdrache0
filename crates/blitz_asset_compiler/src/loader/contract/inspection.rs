//! 開いた文書の契約検査: glTF文書1つに対する適合検査の進行状態を所有する型。担当するのは、集まった指摘と計った概要を持つことと、
//! 指摘を1件記す口を提供することと、走査の工程を呼ぶ順序を決めることである。何が破れなのかは工程ごとのファイルが持つ。
//!
//! 指摘一覧をこの型が所有するのは、全工程が同じ1つの一覧へ書き込むためである。可変の参照を工程の連鎖へ引数で通すと、
//! どの工程がどこまで書けるかが署名から読めなくなり、順序を入れ替えても型が通る。
//!
//! 文書を借用で持つのは、材質スロットの参照が文書の中のプリミティブを指し、文書を所有すると自分自身を参照する形になるためである。
//! 文書を所有するのは呼び出し側の`入力契約を検査するglTFのファイル`である。

use super::super::document::開いた文書;
use super::finding::契約指摘;
use super::inspected_contract::検査する契約;
use super::result::{契約検査概要, 契約検査結果};
use super::slot_materials::材質スロットの参照;
use super::target::対象位置;

pub(super) struct 開いた文書の契約検査<'文書> {
    文書: &'文書 開いた文書,
    概要: Option<契約検査概要>,
    指摘一覧: Vec<契約指摘>,
}

impl<'文書> 開いた文書の契約検査<'文書> {
    pub(super) fn 文書から始める(文書: &'文書 開いた文書) -> Self {
        Self {
            文書,
            概要: None,
            指摘一覧: Vec::new(),
        }
    }

    /// 1件目の破れで止めず、全項目を通す。読み手が1回の実行で直すべき箇所を全部受け取るためである。
    pub(super) fn 全項目を走査する(&mut self, 契約: 検査する契約) {
        self.契約ごとに違う項目を走査する(契約);
        self.どちらの契約でも課す項目を走査する();
    }

    /// 文書とメッシュの並べ方への要求は契約ごとに正反対である。静的シーンは1メッシュだけを許し、群の原型は段の列を要求する。
    fn 契約ごとに違う項目を走査する(&mut self, 契約: 検査する契約) {
        match 契約 {
            検査する契約::静的シーン => {
                self.文書の構成を検査する();
                self.ノード階層を検査する();
                self.先頭メッシュのプリミティブを検査する();
            }
            検査する契約::群の原型 => self.群の原型の項目を走査する(),
            検査する契約::部品 => {
                self.文書の構成を検査する();
                self.ノード階層を検査する();
                self.先頭メッシュのプリミティブを検査する();
                self.接合点の宣言を検査する();
            }
        }
    }

    /// メッシュの並べ方に依らず同じに課す項目。原型は全段が1つのマテリアルを共有するため、
    /// 先頭段から数え上げた材質スロットが原型ぜんたいの材質スロットと一致する。
    fn どちらの契約でも課す項目を走査する(&mut self) {
        let 材質スロット一覧 = 材質スロットの参照::先頭メッシュの材質スロットを数え上げる(self.文書の全体());
        self.先頭メッシュの幾何を読んで概要を計る();
        self.材質の割り当て忘れを検査する();
        self.材質スロットごとのマテリアルを検査する(&材質スロット一覧);
        self.ベースカラーが白のままの材質を検査する(&材質スロット一覧);
        self.読まれないマテリアル宣言を検査する(&材質スロット一覧);
        self.テクスチャの宣言を検査する(&材質スロット一覧);
        self.スキンとアニメーションを検査する();
    }

    pub(super) fn 結果へ畳む(self) -> 契約検査結果 {
        契約検査結果::生成する(self.概要, self.指摘一覧)
    }

    /// 借用したまま返すのは、gltfの各要素の生存期間が文書に結びついており、この型の借用とは無関係だからである。
    pub(super) fn 開いた文書を参照する(&self) -> &'文書 開いた文書 {
        self.文書
    }

    pub(super) fn 文書の全体(&self) -> &'文書 gltf::Document {
        &self.文書.document
    }

    pub(super) fn 概要を記す(&mut self, 概要: 契約検査概要) {
        self.概要 = Some(概要);
    }

    pub(super) fn 違反を記す(&mut self, 位置: 対象位置, 内容: impl Into<String>, 是正方法: impl Into<String>) {
        self.指摘一覧.push(契約指摘::違反を作る(位置, 内容, 是正方法));
    }

    pub(super) fn 警告を記す(&mut self, 位置: 対象位置, 内容: impl Into<String>, 是正方法: impl Into<String>) {
        self.指摘一覧.push(契約指摘::警告を作る(位置, 内容, 是正方法));
    }
}
