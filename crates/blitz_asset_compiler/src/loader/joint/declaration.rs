//! 接合点の宣言: extrasが持つJSONの表1件。担当するのは、その表から接合点を組み立てることである。
//!
//! 導出マクロで構造体へ流し込まないのは、検証を通らない値がそのまま型の中へ座るためである。
//! `Value`として受け、キーごとに型ガードで絞ってから接合点の語彙の型へ渡す(外部境界はunknownで受ける、のRust版)。
//!
//! **座標変換を持たない。読んだ値をそのまま使う。** 宣言はglTFの座標系(Yが上)で書かれる契約であり、
//! Blenderという特定の道具の都合をエンジンの契約へ持ち込まない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「座標系は glTF に合わせる」

use blitz_assembly::{接合点, 接合点エラー, 接合点名, 接合種別, 接合面の姿勢, 接合面の形と寸法};
use blitz_math::{メートル, 位置, 方向, 部品ローカル};
use serde_json::Value;

use super::error::接合点読み取りエラー;
use super::face_read::接合面の形と寸法を読む;
use super::value_read::表から読む;

const 名前のキー: &str = "名前";
const 種別のキー: &str = "種別";
const 位置のキー: &str = "位置";
const 向きのキー: &str = "向き";
const 上方向のキー: &str = "上方向";
const 接合面のキー: &str = "接合面";

/// 前提: 本体はJSONの表である。表であることの判定は`部品の接合点の読み取り`が先に済ませる。
pub(super) struct 接合点の宣言 {
    本体: Value,
}

impl 接合点の宣言 {
    pub(super) fn 表から生成する(本体: Value) -> Self {
        Self { 本体 }
    }

    pub(super) fn 接合点へ組み上げる(&self) -> Result<接合点, 接合点読み取りエラー> {
        let 読み取り = 表から読む::生成する(&self.本体);
        Ok(接合点::生成する(
            接合点名::生成する(読み取り.文字列(名前のキー)?)?,
            接合種別::綴りから読み取る(読み取り.文字列(種別のキー)?)?,
            self.位置を読む()?,
            self.姿勢を読む()?,
            self.接合面を読む()?,
        ))
    }

    fn 位置を読む(&self) -> Result<位置<部品ローカル>, 接合点読み取りエラー> {
        let 成分 = 表から読む::生成する(&self.本体).三成分(位置のキー)?;
        Ok(位置::生成する(
            メートル::生成する(成分[0]),
            メートル::生成する(成分[1]),
            メートル::生成する(成分[2]),
        ))
    }

    fn 姿勢を読む(&self) -> Result<接合面の姿勢, 接合点読み取りエラー> {
        let 読み取り = 表から読む::生成する(&self.本体);
        let 向き = 方向へ写す(読み取り.三成分(向きのキー)?, "向き")?;
        let 上方向 = 方向へ写す(読み取り.三成分(上方向のキー)?, "上方向")?;
        Ok(接合面の姿勢::生成する(向き, 上方向)?)
    }

    fn 接合面を読む(&self) -> Result<接合面の形と寸法, 接合点読み取りエラー> {
        接合面の形と寸法を読む(表から読む::生成する(&self.本体).表(接合面のキー)?)
    }
}

/// 項目名を添えるのは、向きと上方向が同じ形をしており、区別が無いと読み手が直す先を決められないためである。
fn 方向へ写す(成分: [f32; 3], 項目名: &'static str) -> Result<方向<部品ローカル>, 接合点読み取りエラー> {
    let 方向 =
        方向::生成する(成分[0], 成分[1], 成分[2]).map_err(|誤り| 接合点エラー::方向として成り立たない { 項目名, 誤り })?;
    Ok(方向)
}
