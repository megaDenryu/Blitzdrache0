//! 接合点の読み取りの失敗。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! どのキーが破れたかを枝が持つのは、この誤りの読み手が部品を作るBlender側の作者であり、
//! 「宣言のどこを直すか」が分からないと次の操作が決まらないためである。
//!
//! JSONの解析の失敗を文字列で持つのは、`serde_json::Error`が複製できず、この型が複製できないと
//! 契約検査が指摘を集めて並べられなくなるためである。位置の情報は文面に含まれる。

use blitz_assembly::{カタログエラー, 接合点エラー};
use thiserror::Error;

#[derive(Debug, Clone, PartialEq, Error)]
pub enum 接合点読み取りエラー {
    #[error("先頭メッシュを参照するノードが無いため、接合点の宣言を探す先が決まらない")]
    先頭メッシュのノードが無い,

    #[error("接合点の宣言のJSONを解けない: {誤り}")]
    宣言のJSONを解けない { 誤り: String },

    #[error("extrasの「接合点」が配列でない")]
    接合点の宣言が配列でない,

    #[error("{添字}番目の接合点の宣言が表でない")]
    宣言が表でない { 添字: usize },

    #[error("接合点の宣言に「{キー名}」が無い")]
    キーが無い { キー名: &'static str },

    #[error("接合点の宣言の「{キー名}」が文字列でない")]
    値が文字列でない { キー名: &'static str },

    #[error("接合点の宣言の「{キー名}」が数でない")]
    値が数でない { キー名: &'static str },

    #[error("接合点の宣言の「{キー名}」が表でない")]
    値が表でない { キー名: &'static str },

    #[error("接合点の宣言の「{キー名}」が3つの数の配列でない")]
    値が3成分の数でない { キー名: &'static str },

    /// 接合面の形は鍵の組で決まる。幅と高さの組なら矩形、直径なら円である。
    #[error("接合面の形が鍵から決まらない: {事情}。矩形なら幅と高さ、円なら直径だけを書く")]
    接合面の形が鍵から決まらない { 事情: &'static str },

    #[error("接合点の宣言が接合点として成り立たない: {0}")]
    接合点として成り立たない(#[from] 接合点エラー),
}

/// 部品1件をファイルから読むときの失敗。読み取りの破れに、ファイルを開けないことと識別子を作れないことを足したものである。
#[derive(Debug, Error)]
pub enum 部品の読み取りエラー {
    #[error("部品のファイルを開けない: {0}")]
    ファイルを開けない(String),

    #[error("ファイル名から部品IDを作れない: {パス}")]
    ファイル名から部品IDを作れない { パス: String },

    #[error("部品のファイルにメッシュが1つも無い")]
    メッシュが1つも無い,

    #[error("部品の境界箱を頂点位置の宣言から読めない")]
    境界箱を読めない,

    #[error(transparent)]
    接合点を読めない(#[from] 接合点読み取りエラー),

    #[error(transparent)]
    部品定義が成り立たない(#[from] 接合点エラー),

    #[error(transparent)]
    部品IDが成り立たない(#[from] カタログエラー),
}

/// カタログを読み込むときの失敗。どのパスで破れたかを持つのは、並びのどこで止まったかが分からないと読み手が直す先を決められないためである。
#[derive(Debug, Error)]
pub enum 部品カタログの読み込みエラー {
    #[error("{パス}の部品を読めない: {誤り}")]
    部品を読めない {
        パス: String,
        #[source]
        誤り: 部品の読み取りエラー,
    },

    #[error(transparent)]
    カタログを組めない(#[from] カタログエラー),
}
