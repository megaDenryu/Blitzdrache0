//! 接合面の形の破れを拒むことの試験。担当するのは、形が鍵の組から決まらない宣言と、円の直径が正でない宣言を
//! 型付きエラーで拒むことを固定することである。
//!
//! 宣言そのものの破れ(キーの欠け・種別の綴り・姿勢)と分けているのは、こちらが接合面の形の判別だけを見る工程であり、
//! 形を1つ足すたびにここへ件数が増えるためである。宣言の破れの側は形が増えても増えない。

#![allow(clippy::unwrap_used)]

use blitz_assembly::接合点エラー;
use serde_json::json;

use super::declaration_fixture::{基礎の上面の宣言, 読み取りの誤りを得る};
use super::error::接合点読み取りエラー;

/// 矩形と円の鍵を混ぜた宣言を拒む。片方を優先して読むと、作者が2つの形を混ぜて書いた宣言が
/// 黙って一方の形として通り、噛み合いの判定が作者の意図と違う規則で走る。
#[test]
fn 幅と直径を同時に持つ接合面を拒む() {
    let mut 宣言 = 基礎の上面の宣言();
    宣言["接合面"]["直径"] = json!(0.5);
    assert!(matches!(
        読み取りの誤りを得る(宣言),
        接合点読み取りエラー::接合面の形が鍵から決まらない { .. }
    ));
}

#[test]
fn 幅も高さも直径も無い接合面を拒む() {
    let mut 宣言 = 基礎の上面の宣言();
    宣言["接合面"] = json!({ "半径": 0.25 });
    assert!(matches!(
        読み取りの誤りを得る(宣言),
        接合点読み取りエラー::接合面の形が鍵から決まらない { .. }
    ));
}

#[test]
fn 零の接合面の直径を拒む() {
    let mut 宣言 = 基礎の上面の宣言();
    宣言["接合面"] = json!({ "直径": 0.0 });
    assert!(matches!(
        読み取りの誤りを得る(宣言),
        接合点読み取りエラー::接合点として成り立たない(接合点エラー::接合面の寸法が正で有限でない { 辺名: "直径", .. })
    ));
}
