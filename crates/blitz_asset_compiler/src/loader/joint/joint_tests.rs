//! 実データの宣言が接合点として読めることの試験。担当するのは、実物の綴りがそのまま接合点になることと、
//! 読んだ値へ座標変換をかけないことと、十進の綴りを二重に丸めずに単精度で解くことを固定することである。
//!
//! 材料に実データの宣言(基礎の上面。位置が[0, 3, -0]、向きが[0, 1, -0]、接合面が6.0かける5.0)を使うのは、
//! 読み取りが実物の綴りで通ることを、雛形でなく実物で示すためである。
//! ノードの抽出までを通す試験は、extrasを載せたglbを組み立てられる契約検査の側が持つ。

#![allow(clippy::unwrap_used)]

use blitz_assembly::接合種別;
use blitz_math::メートル;
use serde_json::json;

use super::宣言1件を読み取る;
use super::接合点の読み取りの成否;

fn 基礎の上面の宣言() -> serde_json::Value {
    json!({
        "名前": "上面",
        "種別": "上面積層",
        "位置": [0.0, 3.0, -0.0],
        "向き": [0.0, 1.0, -0.0],
        "上方向": [0.0, 0.0, 1.0],
        "接合面": { "幅": 6.0, "高さ": 5.0 }
    })
}

fn 読めた接合点を得る(宣言: serde_json::Value) -> blitz_assembly::接合点 {
    match 宣言1件を読み取る(0, 宣言) {
        接合点の読み取りの成否::読めた(接合点) => 接合点,
        接合点の読み取りの成否::読めなかった { 誤り, .. } => panic!("読めるはずの宣言が読めなかった: {誤り}"),
    }
}

#[test]
fn 実データの宣言をそのまま接合点として読む() {
    let 接合点 = 読めた接合点を得る(基礎の上面の宣言());
    assert_eq!(接合点.名前().綴り(), "上面");
    assert_eq!(接合点.種別(), 接合種別::上面積層);
    assert_eq!(接合点.位置().y(), メートル::生成する(3.0));
    assert_eq!(接合点.接合面().幅(), メートル::生成する(6.0));
    assert_eq!(接合点.接合面().高さ(), メートル::生成する(5.0));
}

/// 座標変換を持たないことの確認。glTFの座標系で書かれた値が、そのまま同じ成分へ入る。
#[test]
fn 読んだ値へ座標変換をかけない() {
    let 接合点 = 読めた接合点を得る(基礎の上面の宣言());
    assert_eq!(接合点.姿勢().法線().y(), 1.0);
    assert_eq!(接合点.姿勢().縦軸().z(), 1.0);
}

/// JSONが綴った十進表記をそのままf32として解く。f64を経由して二重に丸めない。
#[test]
fn 十進の綴りをそのまま単精度として解く() {
    let mut 宣言 = 基礎の上面の宣言();
    宣言["接合面"]["幅"] = json!(0.41999998688697815_f64);
    assert_eq!(読めた接合点を得る(宣言).接合面().幅(), メートル::生成する(0.42));
}
