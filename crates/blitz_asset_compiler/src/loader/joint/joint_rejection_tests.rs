//! 宣言の破れを拒むことの試験。担当するのは、破れがどのキーの破れかを言う型付きエラーになることを固定することである。
//!
//! 正の対照と分けているのは、拒む側が「どの前提を守っているか」の一覧であり、前提を1つ足すたびにここへ1件増えるためである。
//! 正の対照は前提の数が増えても増えない。変わる理由が別である。

#![allow(clippy::unwrap_used)]

use blitz_assembly::接合点エラー;
use serde_json::json;

use super::error::接合点読み取りエラー;
use super::宣言1件を読み取る;
use super::接合点の読み取りの成否;

fn 基礎の上面の宣言() -> serde_json::Value {
    json!({
        "名前": "上面",
        "種別": "上面積層",
        "位置": [0.0, 3.0, -0.0],
        "向き": [0.0, 1.0, -0.0],
        "上方向": [0.0, 0.0, 1.0],
        "接合面": { "幅": 6.0, "高さ": 5.0 }
    })
}

fn 読み取りの誤りを得る(宣言: serde_json::Value) -> 接合点読み取りエラー {
    match 宣言1件を読み取る(0, 宣言) {
        接合点の読み取りの成否::読めた(_) => panic!("拒むはずの宣言が読めてしまった"),
        接合点の読み取りの成否::読めなかった { 誤り, .. } => 誤り,
    }
}

#[test]
fn 表でない宣言を添字つきで拒む() {
    assert_eq!(読み取りの誤りを得る(json!("上面")), 接合点読み取りエラー::宣言が表でない { 添字: 0 });
}

#[test]
fn 欠けたキーをキー名つきで拒む() {
    let mut 宣言 = 基礎の上面の宣言();
    宣言.as_object_mut().unwrap().remove("上方向");
    assert_eq!(読み取りの誤りを得る(宣言), 接合点読み取りエラー::キーが無い { キー名: "上方向" });
}

#[test]
fn 未知の種別の綴りを綴りつきで拒む() {
    let mut 宣言 = 基礎の上面の宣言();
    宣言["種別"] = json!("上面つみかさね");
    assert_eq!(
        読み取りの誤りを得る(宣言),
        接合点読み取りエラー::接合点として成り立たない(接合点エラー::未知の接合種別 {
            綴り: "上面つみかさね".to_string()
        })
    );
}

#[test]
fn 平行な向きと上方向を直交していないとして拒む() {
    let mut 宣言 = 基礎の上面の宣言();
    宣言["上方向"] = json!([0.0, 1.0, 0.0]);
    assert!(matches!(
        読み取りの誤りを得る(宣言),
        接合点読み取りエラー::接合点として成り立たない(接合点エラー::向きと上方向が直交していない { .. })
    ));
}

#[test]
fn 単位長でない向きを項目名つきで拒む() {
    let mut 宣言 = 基礎の上面の宣言();
    宣言["向き"] = json!([0.0, 2.0, 0.0]);
    assert!(matches!(
        読み取りの誤りを得る(宣言),
        接合点読み取りエラー::接合点として成り立たない(接合点エラー::方向として成り立たない { 項目名: "向き", .. })
    ));
}

#[test]
fn 成分が3つでない位置を拒む() {
    let mut 宣言 = 基礎の上面の宣言();
    宣言["位置"] = json!([0.0, 3.0]);
    assert_eq!(読み取りの誤りを得る(宣言), 接合点読み取りエラー::値が3成分の数でない { キー名: "位置" });
}

#[test]
fn 零の接合面の寸法を拒む() {
    let mut 宣言 = 基礎の上面の宣言();
    宣言["接合面"]["幅"] = json!(0.0);
    assert!(matches!(
        読み取りの誤りを得る(宣言),
        接合点読み取りエラー::接合点として成り立たない(接合点エラー::接合面の寸法が正で有限でない { 辺名: "幅", .. })
    ));
}
