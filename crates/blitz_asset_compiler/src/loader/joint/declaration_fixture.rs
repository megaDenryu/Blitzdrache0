//! 宣言の読み取りの試験の材料。実データの宣言1件と、読み取りの成否から値と破れを取り出す口を持つ。
//!
//! 正の対照・宣言の破れ・接合面の形の破れの3つが同じ材料を使うため、この階層が所有して3つへ貸す。
//! 各自が持つと、実データの綴りを直したときに片方だけが古い綴りで通る食い違いが出る。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_assembly::接合点;
use serde_json::{Value, json};

use super::error::接合点読み取りエラー;
use super::宣言1件を読み取る;
use super::接合点の読み取りの成否;

/// 実データの基礎の上面。位置が[0, 3, -0]、向きが[0, 1, -0]、接合面が矩形の6.0かける5.0である。
pub(super) fn 基礎の上面の宣言() -> Value {
    json!({
        "名前": "上面",
        "種別": "上面積層",
        "位置": [0.0, 3.0, -0.0],
        "向き": [0.0, 1.0, -0.0],
        "上方向": [0.0, 0.0, 1.0],
        "接合面": { "幅": 6.0, "高さ": 5.0 }
    })
}

pub(super) fn 読めた接合点を得る(宣言: Value) -> 接合点 {
    match 宣言1件を読み取る(0, 宣言) {
        接合点の読み取りの成否::読めた(接合点) => 接合点,
        接合点の読み取りの成否::読めなかった { 誤り, .. } => panic!("読めるはずの宣言が読めなかった: {誤り}"),
    }
}

pub(super) fn 読み取りの誤りを得る(宣言: Value) -> 接合点読み取りエラー {
    match 宣言1件を読み取る(0, 宣言) {
        接合点の読み取りの成否::読めた(_) => panic!("拒むはずの宣言が読めてしまった"),
        接合点の読み取りの成否::読めなかった { 誤り, .. } => 誤り,
    }
}
