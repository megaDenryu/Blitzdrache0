//! 部品のglTFのファイル: カタログへ積む部品1件を指す役割つきのパス。担当するのは、そのファイルを開いて部品定義を作ることと、
//! ファイル名から部品idを作ることである。
//!
//! 裸のパスでなく役割の型で受けるのは、この口が受け取れるのが部品1件の.glbか.gltfだけであり、
//! 出力先や置き場のパスを渡しても裸の`&Path`では型が通るためである。
//!
//! この型が在るおかげで、カタログを組む側は`gltf`の型に一度も触れずに済む。glTFをどう読むかはローダーの内側に閉じる。

use std::path::{Path, PathBuf};

use blitz_assembly::{部品ID, 部品定義};

use super::super::document;
use super::error::部品の読み取りエラー;
use super::部品の接合点の読み取り;

pub struct 部品のglTFのファイル {
    パス: PathBuf,
}

impl 部品のglTFのファイル {
    pub fn 生成する(パス: &Path) -> Self {
        Self {
            パス: パス.to_path_buf()
        }
    }

    /// 拡張子を落としたファイル名を部品IDにする。宣言表を持たずにカタログを組めるようにするためであり、
    /// 名前がそのまま識別子になることは`part-catalog`の報告の読み手にも分かる。
    pub fn 部品idを作る(&self) -> Result<部品ID, 部品の読み取りエラー> {
        let 幹 = self.パス.file_stem().and_then(|幹| 幹.to_str()).ok_or_else(|| {
            部品の読み取りエラー::ファイル名から部品IDを作れない {
                パス: self.パス.display().to_string(),
            }
        })?;
        Ok(部品ID::生成する(幹)?)
    }

    /// 1件でも読めない接合点があれば型付きエラーで返す。カタログを組む側が半端な接合点の列を受け取ると、
    /// 対の相手の検査が「読めなかった宣言のぶんだけ相手が足りない」という別の破れに化ける。
    pub fn 部品定義を読み取る(&self) -> Result<部品定義, 部品の読み取りエラー> {
        let 文書 = document::文書を開く(&self.パス).map_err(|誤り| 部品の読み取りエラー::ファイルを開けない(誤り.to_string()))?;
        let 読み取り = 部品の接合点の読み取り::先頭メッシュのノードから読み取る(&文書.document)?;
        Ok(部品定義::生成する(読み取り.全件の接合点()?)?)
    }
}
