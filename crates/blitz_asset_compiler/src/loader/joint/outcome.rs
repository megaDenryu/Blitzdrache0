//! 接合点の宣言1件の読み取りの成否。破れても残りの宣言を読み続けるため、失敗を例外でなく値として持つ。
//!
//! 1件目の破れで止めないのは、この読み取りの主な消費者が契約検査であり、検査は見つけた指摘を全件並べる契約だからである。
//! 1件直して再実行するたびに次の1件が出る形だと、直しの往復が宣言の件数だけ要る。

use blitz_assembly::接合点;

use super::error::接合点読み取りエラー;

pub enum 接合点の読み取りの成否 {
    読めた(接合点),
    読めなかった {
        宣言の添字: usize,
        誤り: 接合点読み取りエラー,
    },
}

impl 接合点の読み取りの成否 {
    /// 読み取りの破れを1件の結果へ写す。添字を持つのは、名前が読めなかった宣言を読み手が指せるようにするためである。
    pub(super) fn 結果から生成する(宣言の添字: usize, 結果: Result<接合点, 接合点読み取りエラー>) -> Self {
        match 結果 {
            Ok(接合点) => Self::読めた(接合点),
            Err(誤り) => Self::読めなかった { 宣言の添字, 誤り },
        }
    }

    pub fn 読めた接合点(&self) -> Option<&接合点> {
        match self {
            Self::読めた(接合点) => Some(接合点),
            Self::読めなかった { .. } => None,
        }
    }
}
