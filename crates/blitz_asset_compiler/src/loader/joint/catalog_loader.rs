//! 部品カタログの読み込み係: 部品のglTFのファイルの並びからカタログを組み上げる型。
//! 担当するのは、ファイルを1件ずつ読んで部品IDと定義を作り、組み立て器へ積んで組み上げることである。
//!
//! 組み立て器を可変の参照で外へ持ち出さないのは、積む途中の半端なカタログを触れる範囲を、この型の中へ閉じるためである。
//! 呼び出し側は「パスの並びを渡してカタログを受け取る」だけであり、積む順序も途中の状態も見えない。
//!
//! カタログを読む入口が2つ(被覆の報告と、組み立ての正解表との突き合わせ)あり、どちらも同じ読み方をする。
//! 読み方をここが1箇所で持つことで、片方だけが別の順序で積む形にならない。

use std::path::{Path, PathBuf};

use blitz_assembly::{部品カタログ, 部品カタログ組み立て器};

use super::error::部品カタログの読み込みエラー;
use super::part_file::部品のglTFのファイル;

pub struct 部品カタログの読み込み係 {
    ファイル一覧: Vec<PathBuf>,
}

impl 部品カタログの読み込み係 {
    pub fn パスの並びから生成する(パス一覧: &[PathBuf]) -> Self {
        Self {
            ファイル一覧: パス一覧.to_vec(),
        }
    }

    /// 1件でも読めなければ、どのパスのどの破れかを添えて型付きエラーで返す。半端なカタログを返さない。
    pub fn 組み上げる(&self) -> Result<部品カタログ, 部品カタログの読み込みエラー> {
        let mut 組み立て器 = 部品カタログ組み立て器::空から始める();
        for パス in &self.ファイル一覧 {
            self.部品1件を積む(&mut 組み立て器, パス)?;
        }
        組み立て器.組み上げる().map_err(部品カタログの読み込みエラー::カタログを組めない)
    }

    fn 部品1件を積む(
        &self, 組み立て器: &mut 部品カタログ組み立て器, パス: &Path
    ) -> Result<(), 部品カタログの読み込みエラー> {
        let 読めない = |誤り| 部品カタログの読み込みエラー::部品を読めない {
            パス: パス.display().to_string(),
            誤り,
        };
        let ファイル = 部品のglTFのファイル::生成する(パス);
        let 識別子 = ファイル.部品idを作る().map_err(読めない)?;
        let 定義 = ファイル.部品定義を読み取る().map_err(読めない)?;
        組み立て器
            .部品を1つ積む(識別子, 定義)
            .map_err(部品カタログの読み込みエラー::カタログを組めない)
    }
}
