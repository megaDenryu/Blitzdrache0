//! 接合面の宣言の読み取り。受け取るのは`接合面`のキーが指す表、返すのは接合面の形と寸法である。
//!
//! **形は鍵の組で判別する。** 幅と高さがあれば矩形、直径があれば円である。両方あるものと、どちらも無いものは
//! 型付きエラーで拒む。片方を優先して読むと、作者が2つの形を混ぜて書いた宣言が黙って一方の形として通り、
//! 噛み合いの判定が作者の意図と違う規則で走る。
//!
//! 宣言のキー名をここが1箇所で持つのは、形が増えるたびにキーの綴りが呼び出し側へ散るのを止めるためである。

use blitz_assembly::接合面の形と寸法;
use blitz_math::メートル;
use serde_json::Value;

use super::error::接合点読み取りエラー;
use super::value_read::表から読む;

const 幅のキー: &str = "幅";
const 高さのキー: &str = "高さ";
const 直径のキー: &str = "直径";

pub(super) fn 接合面の形と寸法を読む(面: &Value) -> Result<接合面の形と寸法, 接合点読み取りエラー> {
    let 読み取り = 表から読む::生成する(面);
    let 矩形の鍵がある = 面.get(幅のキー).is_some() || 面.get(高さのキー).is_some();
    let 円の鍵がある = 面.get(直径のキー).is_some();
    match (矩形の鍵がある, 円の鍵がある) {
        (true, false) => Ok(接合面の形と寸法::矩形を生成する(
            メートル::生成する(読み取り.数(幅のキー)?),
            メートル::生成する(読み取り.数(高さのキー)?),
        )?),
        (false, true) => Ok(接合面の形と寸法::円を生成する(
            メートル::生成する(読み取り.数(直径のキー)?),
        )?),
        (true, true) => Err(接合点読み取りエラー::接合面の形が鍵から決まらない {
            事情: "幅または高さと、直径が同時に書かれている",
        }),
        (false, false) => Err(接合点読み取りエラー::接合面の形が鍵から決まらない {
            事情: "幅と高さの組も、直径も書かれていない",
        }),
    }
}
