//! 負でない実数の床を、値を落とさずに符号なし整数へ写す工程。
//!
//! ワークスペースが数値の`as`キャストを禁じているため、ビットの重みを大きい側から参照して求める。
//! 範囲の外と非有限は無言で丸めず値なしを返し、呼び出し側がその場の語彙で型付きエラーにする。
//! 地表高さの升目の割り出しと散布の大域サンプル添字の割り出しが同じ変換を要るため、1つに寄せてある。

/// 0以上65536未満の有限な実数の床をu16にする。範囲の外と非有限は値なしである。
pub(crate) fn 負でない床をu16にする(床: f32) -> Option<u16> {
    if !床.is_finite() || !(0.0..65_536.0).contains(&床) {
        return None;
    }
    let mut 残り = 床;
    let mut 整数 = 0_u16;
    for ビット in (0_u32..16).rev() {
        let 重み = 1_u16 << ビット;
        if 残り >= f32::from(重み) {
            整数 |= 重み;
            残り -= f32::from(重み);
        }
    }
    Some(整数)
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::負でない床をu16にする;

    #[test]
    fn 整数はそのまま写る() {
        assert_eq!(負でない床をu16にする(0.0), Some(0));
        assert_eq!(負でない床をu16にする(1.0), Some(1));
        assert_eq!(負でない床をu16にする(4096.0), Some(4096));
        assert_eq!(負でない床をu16にする(65_535.0), Some(65_535));
    }

    #[test]
    fn 範囲の外と非有限は値なしである() {
        assert_eq!(負でない床をu16にする(-1.0), None);
        assert_eq!(負でない床をu16にする(65_536.0), None);
        assert_eq!(負でない床をu16にする(f32::NAN), None);
        assert_eq!(負でない床をu16にする(f32::INFINITY), None);
    }
}
