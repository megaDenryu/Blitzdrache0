//! 植生定義IDから、焼く原型を1つ引き当てる工程。受け取るのはソースが運ぶ植生定義IDの綴り、
//! 返すのは原型の安定IDと個体の大きさの範囲である。正本の引き当てと実体の枝分かれをここで済ませるため、
//! 群を焼く側は原型だけを見る。
//!
//! 未知の綴りを型付きの失敗にするのは、無言で飛ばすと編集画面で置いた木が絵から消えたまま焼きが成功するためである。

use blitz_engine::アセットID;

use crate::error::アセットコンパイルエラー;
use crate::placement::大きさの範囲;
use crate::runtime_compilation::{全植生定義, 植生の実体, 識別子から植生定義を参照する};

/// 植生定義1件を焼くのに要る2つ。
pub(super) struct 焼く原型 {
    pub(super) 原型の安定id: アセットID,
    pub(super) 大きさの範囲: 大きさの範囲,
}

pub(super) fn 植生定義の識別子から焼く原型を引く(
    植生定義id: &str
) -> Result<焼く原型, アセットコンパイルエラー> {
    let 定義 = 識別子から植生定義を参照する(植生定義id).ok_or_else(|| {
        アセットコンパイルエラー::エディター散布不正(
            format!("未知の植生定義ID: {植生定義id}(正本に在るのは{})", 正本に在る植生定義の綴り()),
        )
    })?;
    match 定義.実体 {
        植生の実体::原型を散らす(識別) => Ok(焼く原型 {
            原型の安定id: アセットID::生成する(識別.安定id())
                .map_err(|原因| アセットコンパイルエラー::エディター散布不正(原因.to_string()))?,
            大きさの範囲: 定義.大きさの範囲,
        }),
        植生の実体::部品を組み立てて散らす(_) => Err(アセットコンパイルエラー::エディター散布不正(format!(
            "植生定義{植生定義id}は部品で組む実体であり、エディターチャンクの散布はまだこの実体を焼けない"
        ))),
    }
}

/// 未知の植生定義IDを告げるときに添える、正本に在る定義の綴り。誤りを見つけた人が正しい綴りを探し回らずに済む。
fn 正本に在る植生定義の綴り() -> String {
    全植生定義()
        .iter()
        .map(|定義| format!("{}={}", 定義.識別子, 定義.表示名))
        .collect::<Vec<_>>()
        .join("・")
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::植生定義の識別子から焼く原型を引く;

    #[test]
    fn 正本に在る針葉樹は原型として引ける() {
        let 引いた = 植生定義の識別子から焼く原型を引く("conifer").unwrap();
        assert_eq!(引いた.原型の安定id.文字列を返す(), "editor_conifer");
    }

    #[test]
    fn 未知の植生定義idは型付きエラーで拒む() {
        let 結果 = 植生定義の識別子から焼く原型を引く("存在しない木");
        assert!(結果.is_err());
    }
}
