//! チャンクの地表材質の重みがどこから来るかと、そこから重みの格子を得る工程。担当するのは、
//! 「重みの欄を持たない形式版1」と「重みの格子ファイルを持つ形式版2」の2つの経路を1つの型で数え上げ、
//! どちらからも同じ形の格子を得ることである。
//!
//! 版の違いを`Option`で表さないのは、値の不在ではなく由来の違いだからである。形式版1が先頭の層だけの格子に
//! なるのは無言の既定値ではなく、その版がまだ塗り分けを持たなかったという意味の写しである。

use std::path::PathBuf;

use crate::error::アセットコンパイルエラー;
use crate::surface_material_weights::{地表材質の重み格子, 地表材質の重み格子を読み込む, 地表材質の重み格子諸元};

pub(crate) enum 地表材質の重みのソース {
    /// 形式版1のチャンク。塗られていないチャンクと同じ「先頭の層だけの重み」として扱う。
    重みを持たない,
    格子ファイル(PathBuf),
}

impl 地表材質の重みのソース {
    /// 増分の鍵が読む、この由来が開くファイル。重みを持たない版は1つも開かない。
    pub(super) fn 開くファイルのパス(&self) -> Option<PathBuf> {
        match self {
            Self::重みを持たない => None,
            Self::格子ファイル(パス) => Some(パス.clone()),
        }
    }

    /// 高さ格子の格子点と1対1に並ぶ重みの格子を得る。並びが食い違う格子は型付きの失敗にする。
    pub(super) fn 重み格子を得る(
        &self, 高さ格子の格子点数: u32
    ) -> Result<地表材質の重み格子, アセットコンパイルエラー> {
        let 格子 = match self {
            Self::重みを持たない => {
                地表材質の重み格子::先頭の層だけで塗り潰して生成する(地表材質の重み格子諸元::生成する(高さ格子の格子点数)?)?
            }
            Self::格子ファイル(パス) => 地表材質の重み格子を読み込む(パス)?,
        };
        格子.高さ格子の格子点数と一致することを確かめる(高さ格子の格子点数)?;
        Ok(格子)
    }
}
