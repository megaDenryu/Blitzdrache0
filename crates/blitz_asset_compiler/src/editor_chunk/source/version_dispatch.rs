//! 本文が名乗る形式版から、その版の型で解析して最新の形へ変換する引き当て。受け取るのはマニフェストの
//! ファイルと本文、返すのは最新の形のエディターチャンクソースである。
//!
//! 引き当てを最新の形の型から分けるのは、変わる理由が違うためである。この引き当ては版を1つ足すたびに伸び、
//! 最新の形は欄が増えたときにだけ変わる。同じファイルに置くと、版を足すたびに型の宣言が押し出される。

use super::manifest_file::エディターチャンクソースのファイル;
use super::{
    version1, version2, version3, version4, エディターチャンクソース, エディターチャンクソースの現在の形式版
};
use crate::error::アセットコンパイルエラー;

pub(super) fn 版を判別して最新の形へ変換する(
    ファイル: &エディターチャンクソースのファイル<'_>,
    本文: &str,
) -> Result<エディターチャンクソース, アセットコンパイルエラー> {
    match ファイル.形式版を読む(本文)? {
        1 => ファイル
            .版の型として解析する::<version1::形式版1のエディターチャンクソース>(本文)?
            .最新へ変換する(ファイル),
        2 => ファイル
            .版の型として解析する::<version2::形式版2のエディターチャンクソース>(本文)?
            .最新へ変換する(ファイル),
        3 => ファイル
            .版の型として解析する::<version3::形式版3のエディターチャンクソース>(本文)?
            .最新へ変換する(ファイル),
        4 => ファイル
            .版の型として解析する::<version4::形式版4のエディターチャンクソース>(本文)?
            .最新へ変換する(ファイル),
        未対応 => Err(ファイル.読み込み失敗のエラーを作る(format!(
            "形式版{未対応}には対応していない（対応版: 1から{エディターチャンクソースの現在の形式版}まで）"
        ))),
    }
}
