//! エディターチャンクソースの散布の欄の検査。担当するのは、形式版3が散布の群と個体を読むこと、
//! 散布を持たない版1と版2が群0件へ写ること、配置識別子が正準化されて読まれることと正準化すると同じになる2件を
//! 重複として拒むことである。置き場と素材の下ごしらえは`version_tests`が持つものを共有する。

#![allow(clippy::unwrap_used)]

use super::version_tests::{ソースを置いて読む, 検査の置き場を用意する, 重み格子を置く, 高さ格子を置く};
use super::エディターチャンクソース;

/// 版3の本文を作る。散布の欄だけを差し替えられるようにするのは、散布の検証だけを狙う検査を書くためである。
fn 版3の本文(散布の群一覧: &str) -> String {
    format!(
        r#"{{"形式版":3,"高さ格子":"地形.heightgrid","地表材質の重み格子":"材質.surfaceweights","建物配置一覧":[],"散布の群一覧":{散布の群一覧}}}"#
    )
}

/// 針葉樹の群1つに個体を並べた散布の群一覧の本文を作る。配置識別子だけを差し替えて識別子の判定を狙う。
fn 針葉樹の群一覧の本文(配置識別子一覧: &[&str]) -> String {
    let 個体一覧: Vec<String> = 配置識別子一覧
        .iter()
        .map(|配置識別子| format!(r#"{{"配置識別子":"{配置識別子}","チャンク原点からの東メートル":1.0,"チャンク原点からの南メートル":2.0}}"#))
        .collect();
    format!(r#"[{{"植生定義ID":"conifer","個体一覧":[{}]}}]"#, 個体一覧.join(","))
}

fn 読めない本文を試す(名前: &str, 本文: &str) {
    let 置き場 = 検査の置き場を用意する(名前);
    高さ格子を置く(&置き場);
    重み格子を置く(&置き場);
    let ソースパス = 置き場.join("チャンク.json");
    std::fs::write(&ソースパス, 本文).unwrap();
    assert!(エディターチャンクソース::ファイルから読む(&ソースパス).is_err());
}

#[test]
fn 形式版1と形式版2は散布を1件も持たない() {
    let 版1 = ソースを置いて読む(
        "version1_scatter",
        r#"{"形式版":1,"高さ格子":"地形.heightgrid","建物配置一覧":[]}"#,
        false,
    );
    assert!(版1.散布の群一覧.is_empty());
    let 版2 = ソースを置いて読む(
        "version2_scatter",
        r#"{"形式版":2,"高さ格子":"地形.heightgrid","地表材質の重み格子":"材質.surfaceweights","建物配置一覧":[]}"#,
        true,
    );
    assert!(版2.散布の群一覧.is_empty());
}

#[test]
fn 形式版3は散布の群と個体を読む() {
    let 本文 = 版3の本文(
        r#"[{"植生定義ID":"conifer","個体一覧":[{"配置識別子":"散布-x0z0-0","チャンク原点からの東メートル":1.5,"チャンク原点からの南メートル":2.5}]}]"#,
    );
    let ソース = ソースを置いて読む("version3", &本文, true);
    assert_eq!(ソース.散布の群一覧.len(), 1);
    let 群 = &ソース.散布の群一覧[0];
    assert_eq!(群.植生定義ID.綴り(), "conifer");
    assert_eq!(群.個体一覧.len(), 1);
    assert_eq!(群.個体一覧[0].配置識別子.綴り(), "散布-x0z0-0");
    assert_eq!(群.個体一覧[0].チャンク原点からの東メートル, 1.5);
    assert_eq!(群.個体一覧[0].チャンク原点からの南メートル, 2.5);
}

#[test]
fn 散布の個体の配置識別子が重複していると拒む() {
    読めない本文を試す("version3_duplicate", &版3の本文(&針葉樹の群一覧の本文(&["同じ", "同じ"])));
}

#[test]
fn 散布の個体の配置識別子は前後の空白を落として読む() {
    let ソース = ソースを置いて読む("scatter_canonical", &版3の本文(&針葉樹の群一覧の本文(&[" 木 "])), true);
    assert_eq!(ソース.散布の群一覧[0].個体一覧[0].配置識別子.綴り(), "木");
}

#[test]
fn 正準化すると同じになる散布の配置識別子はソース検査の時点で重複として拒む() {
    読めない本文を試す("scatter_canonical_duplicate", &版3の本文(&針葉樹の群一覧の本文(&[" 木 ", "木"])));
}

#[test]
fn 空白だけの散布の配置識別子は読み取りが拒む() {
    読めない本文を試す("scatter_blank", &版3の本文(&針葉樹の群一覧の本文(&["  "])));
}

#[test]
fn 空の植生定義idを持つ群は拒む() {
    読めない本文を試す("version3_empty_definition", &版3の本文(r#"[{"植生定義ID":"","個体一覧":[]}]"#));
}
