//! エディターチャンクソースの散布の欄の検査。担当するのは、形式版3が散布の群と個体を読むこと、
//! 散布を持たない版1と版2が群0件へ写ること、配置識別子の重複を拒むことである。
//! 置き場と素材の下ごしらえは`version_tests`が持つものを共有する。

#![allow(clippy::unwrap_used)]

use super::version_tests::{ソースを置いて読む, 検査の置き場を用意する, 重み格子を置く, 高さ格子を置く};
use super::エディターチャンクソース;

/// 版3の本文を作る。散布の欄だけを差し替えられるようにするのは、散布の検証だけを狙う検査を書くためである。
fn 版3の本文(散布の群一覧: &str) -> String {
    format!(
        r#"{{"形式版":3,"高さ格子":"地形.heightgrid","地表材質の重み格子":"材質.surfaceweights","建物配置一覧":[],"散布の群一覧":{散布の群一覧}}}"#
    )
}

#[test]
fn 形式版1と形式版2は散布を1件も持たない() {
    let 版1 = ソースを置いて読む(
        "version1_scatter",
        r#"{"形式版":1,"高さ格子":"地形.heightgrid","建物配置一覧":[]}"#,
        false,
    );
    assert!(版1.散布の群一覧.is_empty());
    let 版2 = ソースを置いて読む(
        "version2_scatter",
        r#"{"形式版":2,"高さ格子":"地形.heightgrid","地表材質の重み格子":"材質.surfaceweights","建物配置一覧":[]}"#,
        true,
    );
    assert!(版2.散布の群一覧.is_empty());
}

#[test]
fn 形式版3は散布の群と個体を読む() {
    let 本文 = 版3の本文(
        r#"[{"植生定義ID":"conifer","個体一覧":[{"配置識別子":"散布-x0z0-0","チャンク原点からの東メートル":1.5,"チャンク原点からの南メートル":2.5}]}]"#,
    );
    let ソース = ソースを置いて読む("version3", &本文, true);
    assert_eq!(ソース.散布の群一覧.len(), 1);
    let 群 = &ソース.散布の群一覧[0];
    assert_eq!(群.植生定義ID, "conifer");
    assert_eq!(群.個体一覧.len(), 1);
    assert_eq!(群.個体一覧[0].配置識別子, "散布-x0z0-0");
    assert_eq!(群.個体一覧[0].チャンク原点からの東メートル, 1.5);
    assert_eq!(群.個体一覧[0].チャンク原点からの南メートル, 2.5);
}

#[test]
fn 散布の個体の配置識別子が重複していると拒む() {
    let 置き場 = 検査の置き場を用意する("version3_duplicate");
    高さ格子を置く(&置き場);
    重み格子を置く(&置き場);
    let ソースパス = 置き場.join("チャンク.json");
    let 本文 = 版3の本文(
        r#"[{"植生定義ID":"conifer","個体一覧":[{"配置識別子":"同じ","チャンク原点からの東メートル":1.0,"チャンク原点からの南メートル":1.0},{"配置識別子":"同じ","チャンク原点からの東メートル":2.0,"チャンク原点からの南メートル":2.0}]}]"#,
    );
    std::fs::write(&ソースパス, 本文).unwrap();
    assert!(エディターチャンクソース::ファイルから読む(&ソースパス).is_err());
}

#[test]
fn 空の植生定義idを持つ群は拒む() {
    let 置き場 = 検査の置き場を用意する("version3_empty_definition");
    高さ格子を置く(&置き場);
    重み格子を置く(&置き場);
    let ソースパス = 置き場.join("チャンク.json");
    std::fs::write(&ソースパス, 版3の本文(r#"[{"植生定義ID":"","個体一覧":[]}]"#)).unwrap();
    assert!(エディターチャンクソース::ファイルから読む(&ソースパス).is_err());
}
