//! 形式版1のエディターチャンクソースの型と、最新の形への変換。担当するのは、この版が持つ欄の並びと、
//! この版に無い欄を最新の形の何へ写すかの決定である。
//!
//! 形式版1は地表材質の重み格子も散布の群も持たない。エディターに地表材質の塗り分けが無かった頃の版であり、
//! 重みは塗られていないチャンクと同じ「先頭の層だけの重み」へ、散布は1本も生えていないチャンクと同じ
//! 「群が0件」へ写す。無言の既定値でなく、版の意味としてここで決める。

use serde::Deserialize;

use super::manifest_file::エディターチャンクソースのファイル;
use super::placement::建物配置ソース;
use super::weight_source::地表材質の重みのソース;
use super::エディターチャンクソース;
use crate::error::アセットコンパイルエラー;

#[derive(Debug, Deserialize)]
pub(super) struct 形式版1のエディターチャンクソース {
    高さ格子: String,
    建物配置一覧: Vec<建物配置ソース>,
}

impl 形式版1のエディターチャンクソース {
    pub(super) fn 最新へ変換する(
        self,
        ファイル: &エディターチャンクソースのファイル<'_>,
    ) -> Result<エディターチャンクソース, アセットコンパイルエラー> {
        エディターチャンクソース::組み立てる(
            ファイル.直下の相対パスを解決する(&self.高さ格子)?,
            地表材質の重みのソース::重みを持たない,
            self.建物配置一覧,
            Vec::new(),
            ファイル,
        )
    }
}
