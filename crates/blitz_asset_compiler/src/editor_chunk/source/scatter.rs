//! 版付きエディターチャンクソースが運ぶ散布の群と個体の型と、群一覧の検証。担当するのは、散布の直列化の形と、
//! 配置識別子の重複と有限でない数値を拒む判定である。植生定義IDの空は`植生定義ID`の読み取りが、配置識別子の
//! 空は`配置識別子`の読み取りが拒むため、ここでは見ない(検査の正本を2つ持たない)。
//! 重複を正準化した綴りで判定するのは、下流の種と姿が同じ綴りで同じ個体を指すためである。
//!
//! 個体が向き・大きさ・高さを持たないのは、その3つを焼く側が導くためである。高さは高さ格子の面から、
//! 向きと大きさは配置識別子から導く。エディターは同じ木を同じ場所へ置いたことだけを伝える。

use std::collections::HashSet;

use serde::Deserialize;

use super::manifest_file::エディターチャンクソースのファイル;
use super::placement_identifier::配置識別子;
use crate::error::アセットコンパイルエラー;
use crate::runtime_compilation::植生定義ID;

/// 同じ植生定義を持つ個体をまとめた群1つ分。
#[derive(Debug, Deserialize)]
#[allow(non_snake_case)]
pub(crate) struct 散布の群ソース {
    pub(crate) 植生定義ID: 植生定義ID,
    pub(crate) 個体一覧: Vec<散布の個体ソース>,
}

/// 散布の個体1件。位置はチャンクの北西角を原点とする実行時のチャンク内座標である。
#[derive(Debug, Deserialize)]
pub(crate) struct 散布の個体ソース {
    pub(crate) 配置識別子: 配置識別子,
    pub(crate) チャンク原点からの東メートル: f32,
    pub(crate) チャンク原点からの南メートル: f32,
}

/// 配置識別子の重複を群をまたいで拒むのは、識別子から個体の向きと大きさを導くためである。
/// 同じ識別子が2件あると、別の場所に立つ2本がまったく同じ姿になる。
pub(super) fn 散布の群一覧を検証する(
    一覧: &[散布の群ソース],
    ファイル: &エディターチャンクソースのファイル<'_>,
) -> Result<(), アセットコンパイルエラー> {
    let mut 出会った配置識別子 = HashSet::new();
    for 群 in 一覧 {
        for 個体 in &群.個体一覧 {
            if !出会った配置識別子.insert(個体.配置識別子.綴り()) {
                return Err(ファイル.読み込み失敗のエラーを作る(format!("散布の個体の識別子{}が重複している", 個体.配置識別子)));
            }
            if !個体.チャンク原点からの東メートル.is_finite() || !個体.チャンク原点からの南メートル.is_finite() {
                return Err(ファイル.読み込み失敗のエラーを作る(format!("散布の個体{}に有限でない数値がある", 個体.配置識別子)));
            }
        }
    }
    Ok(())
}
