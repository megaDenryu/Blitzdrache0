//! エディターチャンクソースの建物配置の欄の検査。担当するのは、配置識別子が正準化されて読まれることと、
//! 正準化すると同じになる2件をソース検査の時点で重複として拒むことである。
//! 置き場と素材の下ごしらえは`version_tests`が持つものを共有する。

#![allow(clippy::unwrap_used)]

use super::version_tests::{ソースを置いて読む, 検査の置き場を用意する, 高さ格子を置く};
use super::エディターチャンクソース;

/// 版1の本文を作る。建物配置の欄だけを差し替えられるようにするのは、建物配置の検証だけを狙う検査を書くためである。
fn 版1の本文(建物配置一覧: &str) -> String {
    format!(r#"{{"形式版":1,"高さ格子":"地形.heightgrid","建物配置一覧":{建物配置一覧}}}"#)
}

fn 建物配置1件(配置識別子: &str) -> String {
    format!(
        r#"{{"配置識別子":"{配置識別子}","建物定義ID":"酒場","チャンク原点からの東メートル":1.0,"チャンク原点からの南メートル":2.0,"向きラジアン":0.0}}"#
    )
}

fn 読めない本文を試す(名前: &str, 本文: &str) {
    let 置き場 = 検査の置き場を用意する(名前);
    高さ格子を置く(&置き場);
    let ソースパス = 置き場.join("チャンク.json");
    std::fs::write(&ソースパス, 本文).unwrap();
    assert!(エディターチャンクソース::ファイルから読む(&ソースパス).is_err());
}

#[test]
fn 配置識別子は前後の空白を落として読む() {
    let 本文 = 版1の本文(&format!("[{}]", 建物配置1件(" 建物 ")));
    let ソース = ソースを置いて読む("placement_canonical", &本文, false);
    assert_eq!(ソース.建物配置一覧[0].配置識別子.綴り(), "建物");
}

#[test]
fn 正準化すると同じになる配置識別子はソース検査の時点で重複として拒む() {
    let 本文 = 版1の本文(&format!("[{},{}]", 建物配置1件(" 建物 "), 建物配置1件("建物")));
    読めない本文を試す("placement_canonical_duplicate", &本文);
}

#[test]
fn 空白だけの配置識別子は読み取りが拒む() {
    読めない本文を試す("placement_blank", &版1の本文(&format!("[{}]", 建物配置1件("  "))));
}
