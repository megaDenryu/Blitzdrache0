//! 形式版4のエディターチャンクソースの型と、最新の形への変換。担当するのは、この版が持つ欄の並びと、
//! 欄から素材のパスを解決する手順である。
//!
//! 形式版4は形式版3へ建物の格子一覧の欄を足した版である。格子を別ファイルへ置かず、このチャンクが使う格子を
//! そのまま抱えるのは、格子の正本が編集データの置き場にあって世界のソースの外にあるためである。抱えることで、
//! 増分の鍵がチャンクのマニフェスト1本を見るだけで格子の変化に追随する。
//!
//! 欄は必須であり、書き手は格子由来の建物を1件も置いていないチャンクにも空の一覧を書き出す
//! (「無し」を欄の不在で表さない)。

use serde::Deserialize;

use super::manifest_file::エディターチャンクソースのファイル;
use super::placement::建物配置ソース;
use super::scatter::散布の群ソース;
use super::weight_source::地表材質の重みのソース;
use super::エディターチャンクソース;
use crate::building_grid_source::建物の格子ソース;
use crate::error::アセットコンパイルエラー;

#[derive(Debug, Deserialize)]
pub(super) struct 形式版4のエディターチャンクソース {
    高さ格子: String,
    地表材質の重み格子: String,
    建物配置一覧: Vec<建物配置ソース>,
    建物の格子一覧: Vec<建物の格子ソース>,
    散布の群一覧: Vec<散布の群ソース>,
}

impl 形式版4のエディターチャンクソース {
    pub(super) fn 最新へ変換する(
        self,
        ファイル: &エディターチャンクソースのファイル<'_>,
    ) -> Result<エディターチャンクソース, アセットコンパイルエラー> {
        let 重みのパス = ファイル.直下の相対パスを解決する(&self.地表材質の重み格子)?;
        エディターチャンクソース::組み立てる(
            ファイル.直下の相対パスを解決する(&self.高さ格子)?,
            地表材質の重みのソース::格子ファイル(重みのパス),
            self.建物配置一覧,
            self.建物の格子一覧,
            self.散布の群一覧,
            ファイル,
        )
    }
}
