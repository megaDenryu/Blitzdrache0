//! チャンクが抱えた建物の格子のソースを、検査を通したベイ格子まで解く工程。受け取るのは格子のソースの並びと
//! マニフェストのファイル、返すのは解けた建物定義の並びである。
//!
//! 読んだ時点で解いておくのは、升目の宣言の破れを焼きの途中でなくマニフェストの読みで表に出すためである。
//! 焼きの途中で落ちると、どのチャンクのどの建物が悪いのかが失敗の文面から遠くなる。

use super::manifest_file::エディターチャンクソースのファイル;
use crate::building_grid_source::{建物の格子ソース, 格子由来の建物定義};
use crate::error::アセットコンパイルエラー;

pub(super) fn 格子のソース一覧を解く(
    ソース一覧: &[建物の格子ソース],
    ファイル: &エディターチャンクソースのファイル<'_>,
) -> Result<Vec<格子由来の建物定義>, アセットコンパイルエラー> {
    ソース一覧
        .iter()
        .map(|ソース| {
            ソース
                .格子由来の建物定義へ解く()
                .map_err(|原因| ファイル.読み込み失敗のエラーを作る(原因.to_string()))
        })
        .collect()
}
