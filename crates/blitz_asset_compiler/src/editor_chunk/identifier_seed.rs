//! 配置識別子から混合関数の種を作る純粋関数。エディターが与えた識別子だけから種が決まるため、
//! 同じ識別子の建物と個体は、世界を焼き直しても同じ姿になる。
//!
//! 綴りの混ぜ方はFNV-1aである。暗号の強さは要らず、短い識別子どうしが近い種にならないことだけが要る。

/// FNV-1aの初期値。
const 初期値: u64 = 0xcbf2_9ce4_8422_2325;

/// FNV-1aの素数。
const 素数: u64 = 0x0000_0100_0000_01b3;

pub(super) fn 配置識別子から混合の種を作る(識別子: &str) -> u64 {
    let mut 種 = 初期値;
    for バイト in 識別子.as_bytes() {
        種 ^= u64::from(*バイト);
        種 = 種.wrapping_mul(素数);
    }
    種
}
