//! エディターチャンクの地面が持つ材質の組み立て。受け取るのは地表材質の重み格子と高さ格子の諸元、
//! 返すのは地表の層の重ね合わせのマテリアルデータである。
//!
//! 層のタイルそのものをここへ入れないのは、タイルが世界に1つだけ置く共有アセットだからである。チャンクのシーンが運ぶのは
//! 重みとタイルの貼り方だけであり、どの絵を貼るかは実行時形式を読んだ後の変換の段が結ぶ
//! (参照: `_doc/設計/マルチマテリアルと材質境界.md`「地表の層の重ね合わせ」)。
//!
//! タイル倍率をチャンクの一辺から導くのは、貼り方を世界のメートルで揃えるためである。チャンクの一辺が変わっても
//! タイル1枚が覆うメートルは変わらず、隣り合うチャンクで模様の細かさが食い違わない。

use blitz_engine::surface_layer_textures::地表層の数;
use blitz_engine::{マテリアルデータ, 地表の層の重ね合わせデータ};

use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子諸元;
use crate::surface_material::weight_texture::重み格子をテクスチャへ写す;
use crate::surface_material::weights::地表材質の重み格子;

/// タイル1枚が覆うワールドのメートル。4層とも同じ値にするのは、層ごとに模様の細かさを変える設計判断がまだ無いためである。
const タイル1枚が覆うメートル: f32 = 4.0;

/// 地面の金属度と粗さ。単色の地面(`地形の単色材質を作る`)と同じ値であり、塗り分けを入れても陰影の出方が変わらない。
const 地面の金属度係数: f32 = 0.0;
const 地面の粗さ係数: f32 = 0.9;

pub(super) fn 地表の層の重ね合わせの材質を作る(
    重み格子: &地表材質の重み格子,
    高さ格子の諸元: 高さ格子諸元,
) -> Result<マテリアルデータ, アセットコンパイルエラー> {
    let 倍率 = チャンクの一辺から倍率を求める(高さ格子の諸元);
    let データ = 地表の層の重ね合わせデータ::生成する(
        重み格子をテクスチャへ写す(重み格子)?,
        [倍率; 地表層の数],
        地面の金属度係数,
        地面の粗さ係数,
    )
    .map_err(|誤り| アセットコンパイルエラー::地表材質不正(誤り.to_string()))?;
    Ok(マテリアルデータ::地表の層の重ね合わせ(データ))
}

/// UVの0から1がチャンクの一辺に対応するため、倍率はその一辺をタイル1枚ぶんのメートルで割った値である。
/// 一辺が零より大きいことは高さ格子諸元の生成が保証するため、割り算は有限の正の値になる。
fn チャンクの一辺から倍率を求める(高さ格子の諸元: 高さ格子諸元) -> f32 {
    高さ格子の諸元.一辺メートル() / タイル1枚が覆うメートル
}
