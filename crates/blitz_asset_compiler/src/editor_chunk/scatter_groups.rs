//! エディターが確定した散布の個体を、植生定義ごとのインスタンス群へ焼く工程。受け取るのは散布の群一覧と
//! 高さ格子と所有チャンクと先頭の描画対象番号、返すのは群の描画対象と置いた個体の数と読んだ素材のファイル一覧である。
//!
//! ソースが運ぶのは水平位置と配置識別子だけであり、天頂成分は高さ格子の面から、向きと大きさは配置識別子から導く。
//! 位置以外をエディターに持たせないのは、木の見え方の規則がエンジンの側の判断であり、
//! 編集画面がそれを保存すると同じ規則の写しが2つになるためである。
//! 植生定義IDの引き当ては`archetype_choice`が持つ。
//! 参照: `_doc/計画/エディターからゲームまでの統合の作戦.md`「段F」

mod archetype_choice;

use std::path::PathBuf;

use blitz_engine::{チャンク座標, 個体配置, 描画対象データ};

use self::archetype_choice::植生定義の識別子から焼く原型を引く;
use super::identifier_seed::配置識別子から混合の種を作る;
use super::source::散布の群ソース;
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子;
use crate::placed_instance_count::置いた個体の数;
use crate::placement::deterministic_value::{用途, 零以上一未満};
use crate::placement::{大きさの範囲, 天頂まわりの回転を作る};
use crate::scene_compiler::ソースアセットのコンパイル係;
use crate::terrain::ground_height;
use crate::vegetation::group_object;

/// 散布の群一覧を焼いた結果。
pub(super) struct 焼いた散布の群一覧 {
    pub(super) 描画対象一覧: Vec<描画対象データ>,
    pub(super) 置いた個体の数: 置いた個体の数,
    pub(super) 参照ファイル一覧: Vec<PathBuf>,
}

impl ソースアセットのコンパイル係<'_> {
    pub(super) fn エディター散布の群を作る(
        &self,
        散布の群一覧: &[散布の群ソース],
        格子: &高さ格子,
        所有チャンク: チャンク座標,
        先頭の描画対象番号: u64,
    ) -> Result<焼いた散布の群一覧, アセットコンパイルエラー> {
        let mut 焼き上がり = 焼いた散布の群一覧 {
            描画対象一覧: Vec::with_capacity(散布の群一覧.len()),
            置いた個体の数: 置いた個体の数::零(),
            参照ファイル一覧: Vec::new(),
        };
        let mut 描画対象番号 = 先頭の描画対象番号;
        for 群ソース in 散布の群一覧 {
            let 原型 = 植生定義の識別子から焼く原型を引く(&群ソース.植生定義ID)?;
            let 配置一覧 = 配置列を作る(群ソース, 格子, 原型.大きさの範囲)?;
            if 配置一覧.is_empty() {
                continue;
            }
            let 原型ソース = self.原型ソースを読み込む(&原型.原型の安定id)?;
            let 群 = group_object::群の描画対象を作る(描画対象番号, 所有チャンク, 原型ソース.段一覧, 原型ソース.材質集合, 配置一覧)?;
            描画対象番号 += 1;
            焼き上がり.置いた個体の数 = 焼き上がり.置いた個体の数.足す(群.置いた個体の数)?;
            焼き上がり.参照ファイル一覧.extend(原型ソース.参照ファイル一覧);
            焼き上がり.描画対象一覧.push(群.描画対象);
        }
        Ok(焼き上がり)
    }
}

/// 個体1件ごとの姿を決める。同じ配置識別子からは常に同じ向きと大きさが出るため、焼き直しても木は動かない。
fn 配置列を作る(
    群ソース: &散布の群ソース,
    格子: &高さ格子,
    大きさの範囲: 大きさの範囲,
) -> Result<Vec<個体配置>, アセットコンパイルエラー> {
    let mut 配置一覧 = Vec::with_capacity(群ソース.個体一覧.len());
    for 個体 in &群ソース.個体一覧 {
        let 東 = 個体.チャンク原点からの東メートル;
        let 南 = 個体.チャンク原点からの南メートル;
        let 高さ = ground_height::地表高さを求める(格子, 東, 南)?;
        let 種 = 配置識別子から混合の種を作る(&個体.配置識別子);
        let 角度 = 零以上一未満(種, 0, 用途::向き) * std::f32::consts::TAU;
        let 倍率 = 大きさの範囲.零以上一未満の値から求める(零以上一未満(種, 0, 用途::大きさ));
        配置一覧.push(個体配置::生成する([東, 高さ, 南], 天頂まわりの回転を作る(角度), [倍率; 3])?);
    }
    Ok(配置一覧)
}
