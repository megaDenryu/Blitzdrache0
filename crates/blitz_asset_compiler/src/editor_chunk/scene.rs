//! エディターチャンク1件分のシーンを組み立てる工程。受け取るのは版付きソースと所有チャンクとマニフェストのパス、
//! 返すのは地面と建物の群と散布の群を載せたシーンである。
//!
//! 描画対象番号を地面・建物・散布の順で配るのは、番号がシーンの中で一意でなければならず、
//! 配る規律を1箇所へ集めるためである。建物の展開は`building_groups`が、散布の群は`scatter_groups`が持つ。

use std::path::PathBuf;

use blitz_engine::{シーンデータ, チャンク座標};

use super::source::エディターチャンクソース;
use crate::assembled_scene::組み立てたシーン;
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子を読み込む;
use crate::placed_instance_count::置いた個体の数;
use crate::scene_compiler::ソースアセットのコンパイル係;
use crate::terrain::ground_object;

use super::ground_material::地表の層の重ね合わせの材質を作る;

const 地面の描画対象番号: u64 = 0;

impl ソースアセットのコンパイル係<'_> {
    pub(super) fn エディターチャンクのシーンを組み立てる(
        &self,
        ソース: &エディターチャンクソース,
        所有チャンク: チャンク座標,
        マニフェストパス: PathBuf,
    ) -> Result<組み立てたシーン, アセットコンパイルエラー> {
        let 格子 = 高さ格子を読み込む(ソース.高さ格子パス())?;
        // 重みの並びが高さ格子と1対1であることを焼く前に確かめる。食い違ったまま焼くと塗り分けが地形の上を引き伸ばされて載る。
        let 重み格子 = ソース.地表材質の重み格子を得る(格子.諸元().格子点数())?;
        let 材質 = 地表の層の重ね合わせの材質を作る(&重み格子, 格子.諸元())?;
        let 地面 = ground_object::高さ格子から地面の描画対象を作る(&格子, 所有チャンク, 地面の描画対象番号, 材質)?;
        let mut 参照一覧 = vec![マニフェストパス];
        参照一覧.extend(ソース.素材ファイルのパス一覧());

        let mut 描画対象一覧 = Vec::new();
        let mut 置いた個体の数 = 置いた個体の数::零();
        let mut 次の描画対象番号 = 地面の描画対象番号 + 1;
        if !ソース.建物配置一覧.is_empty() {
            let 群一覧 = self.エディター建物の部品ごとの群を作る(&ソース.建物配置一覧, &格子, 所有チャンク, 次の描画対象番号)?;
            置いた個体の数 = 置いた個体の数.足す(群一覧.置いた個体の数())?;
            次の描画対象番号 += 群一覧.件数を数える()?;
            let (建物の描画対象一覧, 部品の参照一覧) = 群一覧.描画対象と参照ファイルへ畳む();
            参照一覧.extend(部品の参照一覧);
            描画対象一覧.extend(建物の描画対象一覧);
        }
        let 散布 = self.エディター散布の群を作る(&ソース.散布の群一覧, &格子, 所有チャンク, 次の描画対象番号)?;
        置いた個体の数 = 置いた個体の数.足す(散布.置いた個体の数)?;
        参照一覧.extend(散布.参照ファイル一覧);
        描画対象一覧.extend(散布.描画対象一覧);

        let シーン = シーンデータ::生成する(地面, 描画対象一覧, 参照一覧, None, Vec::new());
        Ok(組み立てたシーン::置いた個体の数を添えて生成する(
            シーン,
            置いた個体の数,
        ))
    }
}
