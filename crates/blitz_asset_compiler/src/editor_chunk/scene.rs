//! エディター建物を安定識別子由来の種で展開し、部品の種類ごとの群へまとめて地面へ載せる。

use std::path::PathBuf;

use blitz_assembly::{展開器, 部品ごとの配置の集約};
use blitz_engine::{アセットID, シーンデータ, チャンク座標, 個体配置};

use super::source::エディターチャンクソース;
use crate::assembled_scatter::groups;
use crate::assembled_scene::組み立てたシーン;
use crate::assembly_parts::組み立てに使う部品一式;
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子を読み込む;
use crate::placement::天頂まわりの回転を作る;
use crate::runtime_compilation::{全建物の部品識別一覧, 識別子で引く};
use crate::scene_compiler::ソースアセットのコンパイル係;
use crate::terrain::{ground_height, ground_object};

const 地面の描画対象番号: u64 = 0;
const 草地のベースカラー係数: [f32; 4] = [0.13, 0.19, 0.09, 1.0];

impl ソースアセットのコンパイル係<'_> {
    pub(super) fn エディターチャンクのシーンを組み立てる(
        &self,
        ソース: &エディターチャンクソース,
        所有チャンク: チャンク座標,
        マニフェストパス: PathBuf,
    ) -> Result<組み立てたシーン, アセットコンパイルエラー> {
        let 格子 = 高さ格子を読み込む(ソース.高さ格子パス())?;
        let 部品id一覧 = 全建物の部品識別一覧()
            .into_iter()
            .map(|(安定id, _)| アセットID::生成する(安定id).map_err(|原因| エディター建物のエラー(原因.to_string())))
            .collect::<Result<Vec<_>, _>>()?;
        let 部品一式 = 組み立てに使う部品一式::宣言から読み取る(self, &部品id一覧)?;
        let 展開器 = 展開器::カタログを持たせて生成する(部品一式.カタログを組み上げる()?);
        let mut 集約 = 部品ごとの配置の集約::空から始める();
        for 配置 in &ソース.建物配置一覧 {
            let 定義 =
                識別子で引く(&配置.建物定義ID).ok_or_else(|| エディター建物のエラー(format!("未知の建物定義ID: {}", 配置.建物定義ID)))?;
            let 高さ = ground_height::地表高さを求める(&格子, 配置.チャンク原点からの東メートル, 配置.チャンク原点からの南メートル)?;
            let 根 = 個体配置::生成する(
                [配置.チャンク原点からの東メートル, 高さ, 配置.チャンク原点からの南メートル],
                天頂まわりの回転を作る(配置.向きラジアン),
                [1.0; 3],
            )?;
            let (規則, 種の起点) = 定義.規則.規則と種の起点を組む().map_err(エディター建物のエラー)?;
            let 種 = 種の起点.個体の番号で分けた種を作る(識別子の安定ハッシュ(&配置.配置識別子));
            let 配置表 = 展開器
                .規則から展開する(&規則, 種, 根)
                .map_err(|原因| エディター建物のエラー(format!("建物{}を展開できない: {原因}", 配置.配置識別子)))?;
            集約.配置表を1件取り込む(&配置表);
        }

        let 地面 = ground_object::高さ格子から地面の描画対象を作る(&格子, 所有チャンク, 地面の描画対象番号, 草地のベースカラー係数)?;
        let 群一覧 = groups::集約から群を作る(self, 所有チャンク, 地面の描画対象番号 + 1, &部品一式, &集約)?;
        let 置いた個体の数 = 群一覧.置いた個体の数();
        let (群の描画対象一覧, 部品の参照一覧) = 群一覧.描画対象と参照ファイルへ畳む();
        let mut 参照一覧 = vec![マニフェストパス, ソース.高さ格子パス().to_path_buf()];
        参照一覧.extend(部品の参照一覧);
        let シーン = シーンデータ::生成する(地面, 群の描画対象一覧, 参照一覧, None, Vec::new());
        Ok(組み立てたシーン::置いた個体の数を添えて生成する(
            シーン,
            置いた個体の数,
        ))
    }
}

fn 識別子の安定ハッシュ(識別子: &str) -> u64 {
    let mut ハッシュ = 0xcbf2_9ce4_8422_2325_u64;
    for バイト in 識別子.as_bytes() {
        ハッシュ ^= u64::from(*バイト);
        ハッシュ = ハッシュ.wrapping_mul(0x0000_0100_0000_01b3);
    }
    ハッシュ
}

fn エディター建物のエラー(原因: String) -> アセットコンパイルエラー {
    アセットコンパイルエラー::エディター建物配置不正(原因)
}
