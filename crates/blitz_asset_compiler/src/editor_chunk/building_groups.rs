//! エディター建物を展開し、部品の種類ごとの群と静的物理形状へまとめる工程。受け取るのは版付きソースと高さ格子と
//! 所有チャンクと先頭の描画対象番号、返すのは部品の種類ごとの群の一覧とチャンクの静的物理形状である。
//!
//! 描く形と当たる形を同じ展開から作るのは、2度展開すると規則の引きが分かれて別の家になりうるためである。
//!
//! 建物の根の天頂成分を高さ格子から求めるのは、エディターが水平位置と向きだけを保存し、
//! 建物が据わる高さをその場所の地面から決めるためである。
//!
//! 由来ごとに違うのは組み立て手順の作り方だけである。宣言の規則は配置の安定識別子から作った種で候補を引き、
//! 格子は人が置いた升目をそのまま写す。格子の由来が種を使わないのは、升目1つずつが既に人の決定だからである。

use blitz_assembly::{展開器, 組み立て手順, 部品ごとの配置の集約, 部品ごとの配置表};
use blitz_engine::static_shape::衝突対象の安定識別子;
use blitz_engine::{チャンク座標, 個体配置};

use super::building_bake_result::建物を焼いた結果;
use super::building_definitions::{
    エディター建物のエラーを作る, チャンクが焼く建物, 建物の実体一覧が使う部品の識別子一覧を作る, 建物配置一覧が指す建物の実体を引く,
};
use super::identifier_seed::配置識別子から混合の種を作る;
use super::source::{エディターチャンクソース, 建物配置ソース};
use crate::assembled_scatter::groups;
use crate::assembly_parts::組み立てに使う部品一式;
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子;
use crate::placement::天頂まわりの回転を作る;
use crate::runtime_compilation::骨格方式の部品の綴りを組む;
use crate::scene_compiler::ソースアセットのコンパイル係;
use crate::static_physics::{建物の静的物理形状の組み手, 部品ごとの境界箱の表, 静的物理形状のコンパイルエラー};
use crate::terrain::ground_height;

impl ソースアセットのコンパイル係<'_> {
    pub(super) fn エディター建物の群と静的物理形状を作る(
        &self,
        ソース: &エディターチャンクソース,
        格子: &高さ格子,
        所有チャンク: チャンク座標,
        先頭の描画対象番号: u64,
    ) -> Result<建物を焼いた結果, アセットコンパイルエラー> {
        let 実体一覧 = 建物配置一覧が指す建物の実体を引く(ソース)?;
        let 部品の識別子一覧 = 建物の実体一覧が使う部品の識別子一覧を作る(&実体一覧)?;
        let 部品一式 = 組み立てに使う部品一式::宣言から読み取る(self, &部品の識別子一覧)?;
        let 展開器 = 展開器::カタログを持たせて生成する(部品一式.カタログを組み上げる()?);
        let mut 集約 = 部品ごとの配置の集約::空から始める();
        let mut 形状の組み手 =
            建物の静的物理形状の組み手::境界箱の表を持たせて始める(部品ごとの境界箱の表::部品一式から読む(&部品一式)?);
        for (配置, 実体) in ソース.建物配置一覧.iter().zip(&実体一覧) {
            let 根 = 建物の根の配置を求める(配置, 格子)?;
            let 配置表 = 建物1件を展開する(&展開器, 配置, 実体, 根)?;
            let 安定識別子 = 衝突対象の安定識別子::生成する(&配置.配置識別子).map_err(静的物理形状のコンパイルエラー::from)?;
            形状の組み手.建物を1棟取り込む(安定識別子, &配置表)?;
            集約.配置表を1件取り込む(&配置表);
        }
        Ok(建物を焼いた結果 {
            群一覧: groups::集約から群を作る(self, 所有チャンク, 先頭の描画対象番号, &部品一式, &集約)?,
            静的物理形状: 形状の組み手.組み上げる()?,
        })
    }
}

fn 建物の根の配置を求める(
    配置: &建物配置ソース, 格子: &高さ格子
) -> Result<個体配置, アセットコンパイルエラー> {
    let 高さ = ground_height::地表高さを求める(格子, 配置.チャンク原点からの東メートル, 配置.チャンク原点からの南メートル)?;
    Ok(個体配置::生成する(
        [配置.チャンク原点からの東メートル, 高さ, 配置.チャンク原点からの南メートル],
        天頂まわりの回転を作る(配置.向きラジアン),
        [1.0; 3],
    )?)
}

fn 建物1件を展開する(
    展開器: &展開器,
    配置: &建物配置ソース,
    実体: &チャンクが焼く建物<'_>,
    根: 個体配置,
) -> Result<部品ごとの配置表, アセットコンパイルエラー> {
    match 実体 {
        チャンクが焼く建物::宣言の規則(定義) => {
            let (規則, 種の起点) = 定義.規則.規則と種の起点を組む().map_err(エディター建物のエラーを作る)?;
            let 種 = 種の起点.個体の番号で分けた種を作る(配置識別子から混合の種を作る(&配置.配置識別子));
            展開器.規則から展開する(&規則, 種, 根)
        }
        チャンクが焼く建物::ベイ格子(定義) => 展開器.手順を展開する(&格子から手順を写す(定義)?, 根),
    }
    .map_err(|原因| エディター建物のエラーを作る(format!("建物{}を展開できない: {原因}", 配置.配置識別子)))
}

fn 格子から手順を写す(
    定義: &crate::building_grid_source::格子由来の建物定義,
) -> Result<組み立て手順, アセットコンパイルエラー> {
    let 綴り = 骨格方式の部品の綴りを組む().map_err(エディター建物のエラーを作る)?;
    Ok(定義.格子().組み立て手順へ写す(&綴り))
}
