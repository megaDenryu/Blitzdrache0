//! エディター建物を安定識別子由来の種で展開し、部品の種類ごとの群へまとめる工程。
//! 受け取るのは建物配置一覧と高さ格子と所有チャンクと先頭の描画対象番号、返すのは部品の種類ごとの群の一覧である。
//!
//! 建物の根の天頂成分を高さ格子から求めるのは、エディターが水平位置と向きだけを保存し、
//! 建物が据わる高さをその場所の地面から決めるためである。

use blitz_assembly::{展開器, 部品ごとの配置の集約};
use blitz_engine::{チャンク座標, 個体配置};

use super::building_definitions::{
    エディター建物のエラーを作る, 建物定義一覧が使う部品の識別子一覧を作る, 建物配置一覧が指す建物定義を引く
};
use super::identifier_seed::配置識別子から混合の種を作る;
use super::source::建物配置ソース;
use crate::assembled_scatter::groups;
use crate::assembly_parts::組み立てに使う部品一式;
use crate::error::アセットコンパイルエラー;
use crate::height_grid::高さ格子;
use crate::placement::天頂まわりの回転を作る;
use crate::scene_compiler::ソースアセットのコンパイル係;
use crate::terrain::ground_height;

impl ソースアセットのコンパイル係<'_> {
    pub(super) fn エディター建物の部品ごとの群を作る(
        &self,
        建物配置一覧: &[建物配置ソース],
        格子: &高さ格子,
        所有チャンク: チャンク座標,
        先頭の描画対象番号: u64,
    ) -> Result<groups::部品ごとの群一覧, アセットコンパイルエラー> {
        let 定義一覧 = 建物配置一覧が指す建物定義を引く(建物配置一覧)?;
        let 部品の識別子一覧 = 建物定義一覧が使う部品の識別子一覧を作る(&定義一覧)?;
        let 部品一式 = 組み立てに使う部品一式::宣言から読み取る(self, &部品の識別子一覧)?;
        let 展開器 = 展開器::カタログを持たせて生成する(部品一式.カタログを組み上げる()?);
        let mut 集約 = 部品ごとの配置の集約::空から始める();
        for (配置, 定義) in 建物配置一覧.iter().zip(定義一覧) {
            let 高さ = ground_height::地表高さを求める(格子, 配置.チャンク原点からの東メートル, 配置.チャンク原点からの南メートル)?;
            let 根 = 個体配置::生成する(
                [配置.チャンク原点からの東メートル, 高さ, 配置.チャンク原点からの南メートル],
                天頂まわりの回転を作る(配置.向きラジアン),
                [1.0; 3],
            )?;
            let (規則, 種の起点) = 定義.規則.規則と種の起点を組む().map_err(エディター建物のエラーを作る)?;
            let 種 = 種の起点.個体の番号で分けた種を作る(配置識別子から混合の種を作る(&配置.配置識別子));
            let 配置表 = 展開器
                .規則から展開する(&規則, 種, 根)
                .map_err(|原因| エディター建物のエラーを作る(format!("建物{}を展開できない: {原因}", 配置.配置識別子)))?;
            集約.配置表を1件取り込む(&配置表);
        }
        groups::集約から群を作る(self, 所有チャンク, 先頭の描画対象番号, &部品一式, &集約)
    }
}
