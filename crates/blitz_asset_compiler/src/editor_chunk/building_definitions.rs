//! エディターチャンクの建物配置一覧から、焼くのに要る建物の実体とその部品の識別子を解決する工程。
//! 受け取るのは版付きソースが持つ建物配置一覧と、そのソースが抱える格子であり、返すのは配置と同じ並びの
//! 建物の実体と、そこから重複を除いた部品の識別子一覧である。
//!
//! 実体を判別共用体にするのは、同じチャンクの中に宣言の規則から組む建物と、人が編集した格子から組む建物が
//! 混ざるためである。どちらかに決め打つと、片方の建物だけが黙って抜け落ちる。
//! 未知の建物定義IDは無言で飛ばさず、型付きの失敗にする。

use blitz_engine::アセットID;

use super::source::{エディターチャンクソース, 建物配置ソース};
use crate::building_grid_source::格子由来の建物定義;
use crate::error::アセットコンパイルエラー;
use crate::runtime_compilation::{建物定義の正本, 識別子から建物定義を参照する, 骨格方式の全部品の一覧};

/// チャンクが焼く建物1件の実体。組み立て手順の作り方だけが枝で違う。
pub(super) enum チャンクが焼く建物<'ソース> {
    宣言の規則(建物定義の正本),
    ベイ格子(&'ソース 格子由来の建物定義),
}

pub(super) fn 建物配置一覧が指す建物の実体を引く<'ソース>(
    ソース: &'ソース エディターチャンクソース,
) -> Result<Vec<チャンクが焼く建物<'ソース>>, アセットコンパイルエラー> {
    ソース.建物配置一覧.iter().map(|配置| 配置1件の実体を引く(ソース, 配置)).collect()
}

fn 配置1件の実体を引く<'ソース>(
    ソース: &'ソース エディターチャンクソース,
    配置: &建物配置ソース,
) -> Result<チャンクが焼く建物<'ソース>, アセットコンパイルエラー> {
    if let Some(格子) = ソース.建物の格子を引く(&配置.建物定義ID) {
        return Ok(チャンクが焼く建物::ベイ格子(格子));
    }
    識別子から建物定義を参照する(配置.建物定義ID.綴り())
        .map(チャンクが焼く建物::宣言の規則)
        .ok_or_else(|| エディター建物のエラーを作る(format!("未知の建物定義ID: {}", 配置.建物定義ID)))
}

/// このチャンクに現れる建物が使う部品だけを、重複を除いて並べる。全建物の部品を無条件に読むと、
/// 建物を1件も持たないチャンクでも部品のglTFを全部開くことになる。
pub(super) fn 建物の実体一覧が使う部品の識別子一覧を作る(
    実体一覧: &[チャンクが焼く建物<'_>],
) -> Result<Vec<アセットID>, アセットコンパイルエラー> {
    let mut 一覧: Vec<アセットID> = Vec::new();
    for 実体 in 実体一覧 {
        let 部品一覧 = match 実体 {
            チャンクが焼く建物::宣言の規則(定義) => 定義.規則.部品一覧(),
            チャンクが焼く建物::ベイ格子(_) => 骨格方式の全部品の一覧(),
        };
        for 部品 in 部品一覧 {
            let 識別子 = アセットID::生成する(部品.安定id()).map_err(|原因| エディター建物のエラーを作る(原因.to_string()))?;
            if !一覧.contains(&識別子) {
                一覧.push(識別子);
            }
        }
    }
    Ok(一覧)
}

pub(super) fn エディター建物のエラーを作る(原因: String) -> アセットコンパイルエラー {
    アセットコンパイルエラー::エディター建物配置不正(原因)
}
