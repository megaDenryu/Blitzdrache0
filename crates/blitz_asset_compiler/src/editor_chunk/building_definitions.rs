//! エディターチャンクの建物配置一覧から、焼くのに要る建物定義とその部品の識別子を解決する工程。
//! 受け取るのは版付きソースが持つ建物配置一覧であり、返すのは配置と同じ並びの建物定義の正本と、
//! そこから重複を除いた部品の識別子一覧である。未知の建物定義IDは無言で飛ばさず、型付きの失敗にする。

use blitz_engine::アセットID;

use super::source::建物配置ソース;
use crate::error::アセットコンパイルエラー;
use crate::runtime_compilation::{建物定義の正本, 識別子で引く};

pub(super) fn 建物配置一覧が指す建物定義を引く(
    建物配置一覧: &[建物配置ソース],
) -> Result<Vec<建物定義の正本>, アセットコンパイルエラー> {
    建物配置一覧
        .iter()
        .map(|配置| {
            識別子で引く(配置.建物定義ID.綴り()).ok_or_else(|| エディター建物のエラー(format!("未知の建物定義ID: {}", 配置.建物定義ID)))
        })
        .collect()
}

/// このチャンクに現れる建物定義が使う部品だけを、重複を除いて並べる。全建物の部品を無条件に読むと、
/// 建物を1件も持たないチャンクでも部品のglTFを全部開くことになる。
pub(super) fn 建物定義一覧が使う部品の識別子一覧を作る(
    定義一覧: &[建物定義の正本],
) -> Result<Vec<アセットID>, アセットコンパイルエラー> {
    let mut 一覧: Vec<アセットID> = Vec::new();
    for 定義 in 定義一覧 {
        for 部品 in 定義.規則.部品一覧() {
            let 識別子 = アセットID::生成する(部品.安定id()).map_err(|原因| エディター建物のエラー(原因.to_string()))?;
            if !一覧.contains(&識別子) {
                一覧.push(識別子);
            }
        }
    }
    Ok(一覧)
}

pub(super) fn エディター建物のエラー(原因: String) -> アセットコンパイルエラー {
    アセットコンパイルエラー::エディター建物配置不正(原因)
}
