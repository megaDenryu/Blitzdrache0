//! カタログの報告: 組み上がったカタログを読み手が見る文面へ写す型。担当するのは並べる項目と綴りだけであり、
//! 数を数えるのはカタログの側である。
//!
//! 種別ごとの員数を0件も含めて全種別ぶん出すのは、検査が空振りしている範囲を報告に出すためである。
//! 件数0の行が「この種別はまだ実データで確かめていない」ことの記録になる。
//! 様式が未定の種別を別に並べるのは、員数が0でなくても接合を組めない種別があるためである。

use std::fmt;

use blitz_assembly::{接合の様式, 部品カタログ};

pub struct カタログの報告 {
    部品数: usize,
    接合点の総数: usize,
    種別ごとの行: Vec<String>,
    未出現の種別: Vec<String>,
    様式が未定の種別: Vec<String>,
}

impl カタログの報告 {
    pub fn カタログから作る(カタログ: &部品カタログ) -> Self {
        let 員数一覧 = カタログ.種別ごとの員数一覧();
        Self {
            部品数: カタログ.部品数(),
            接合点の総数: カタログ.接合点の総数(),
            種別ごとの行: 員数一覧
                .iter()
                .map(|員数| format!("  {}: {}件 (様式は{})", 員数.種別, 員数.件数, 員数.種別.様式().綴り()))
                .collect(),
            未出現の種別: 員数一覧.iter().filter(|員数| 員数.件数 == 0).map(|員数| 員数.種別.to_string()).collect(),
            様式が未定の種別: 員数一覧
                .iter()
                .filter(|員数| 員数.種別.様式() == 接合の様式::未定)
                .map(|員数| 員数.種別.to_string())
                .collect(),
        }
    }
}

impl fmt::Display for カタログの報告 {
    fn fmt(&self, 出力: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(出力, "部品{}件、接合点{}件", self.部品数, self.接合点の総数)?;
        writeln!(出力, "種別ごとの員数:")?;
        for 行 in &self.種別ごとの行 {
            writeln!(出力, "{行}")?;
        }
        writeln!(出力, "実データに現れていない種別: {}", 並びを綴る(&self.未出現の種別))?;
        writeln!(出力, "様式がまだ決まっていない種別: {}", 並びを綴る(&self.様式が未定の種別))
    }
}

fn 並びを綴る(一覧: &[String]) -> String {
    if 一覧.is_empty() {
        return "無し".to_string();
    }
    一覧.join("・")
}
