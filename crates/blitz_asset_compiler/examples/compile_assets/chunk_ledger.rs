//! 生成台帳を見ながらコンパイル対象を焼く工程。受け取るのは出力ルートとコンパイル時カタログと対象の一覧、
//! 返すのは焼き直しの勘定であり、実行時カタログへの登録もここで行う。
//! 対象1件の処理は`one_target`が、焼く手順は`bake_one`が、据え置いた対象の項目を前回のカタログから写す手順は
//! `carried_entry`が持つ。
//!
//! 増分の鍵にソース依存の一式を使うのは、チャンク1つが読む材料が1つとは限らないためである。前回の焼き上がりが
//! 何を読んだかは前回のカタログの依存一覧に残っており、その全部が変わっていなければ焼き直す理由が無い。
//!
//! 対象ごとの処理を並列にしてよいのは、1つの対象のコンパイルが他の対象の生成物を1つも読まないためである。
//! 実行時カタログへの登録と台帳への記録は、並列の結果が揃ってから対象の並びの順で行う。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

mod bake_one;
mod carried_entry;
mod one_target;

use std::path::Path;

use blitz_asset_compiler::{テクスチャ格納方針, 焼き直しの勘定, 生成台帳, 生成台帳の見出し, 種の由来};
use blitz_engine::カタログ;
use rayon::iter::{IntoParallelRefIterator, ParallelIterator};

use super::catalog::コンパイル対象;

/// その対象を増分の台帳で据え置ける単位として扱うかどうか。チャンク世界のチャンクだけが座標で台帳へ記録できる。
/// 世界に1つ据えるアセットは所有チャンクが原点で揃って座標では区別できないため、毎回焼く。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 台帳での扱い {
    チャンクとして記録する,
    毎回焼く,
}

pub(super) fn 台帳を見ながら対象一覧を焼く(
    出力ルート: &Path,
    コンパイル時カタログ: &カタログ,
    対象一覧: &[コンパイル対象],
    方針: テクスチャ格納方針,
    実行時カタログ: &mut カタログ,
) -> Result<焼き直しの勘定, String> {
    let 見出し = 生成台帳の見出し::実行中の生成器から作る(種の由来::種を持たない).map_err(|誤り| 誤り.to_string())?;
    let 前回の台帳 = 生成台帳::出力ルートから読み込む(出力ルート, 見出し).map_err(|誤り| 誤り.to_string())?;
    let 前回のカタログ = carried_entry::前回の実行時カタログを読む(出力ルート);
    let 仕上がり一覧 = 対象一覧
        .par_iter()
        .map(|対象| one_target::対象1件を仕上げる(コンパイル時カタログ, 対象, 方針, &前回の台帳, 前回のカタログ.as_ref()))
        .collect::<Result<Vec<_>, String>>()?;
    let mut 今回の台帳 = 生成台帳::見出しを与えて空を作る(見出し);
    let mut 判定一覧 = Vec::with_capacity(仕上がり一覧.len());
    for (対象, 仕上がり) in 対象一覧.iter().zip(仕上がり一覧) {
        実行時カタログ.詳細を登録する(対象.id.clone(), 仕上がり.実行時パス, 仕上がり.ソース依存一覧, 仕上がり.メタデータ);
        if let Some(内容ハッシュ) = 仕上がり.台帳へ記録する内容ハッシュ {
            今回の台帳.内容ハッシュを記録する(対象.所有チャンク, 内容ハッシュ);
        }
        判定一覧.extend(仕上がり.焼き直しの判定);
    }
    今回の台帳.出力ルートへ書き出す(出力ルート).map_err(|誤り| 誤り.to_string())?;
    Ok(焼き直しの勘定::判定の一覧から数える(判定一覧.into_iter()))
}
