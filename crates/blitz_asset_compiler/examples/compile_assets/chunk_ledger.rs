//! 生成台帳を見ながらコンパイル対象を焼く工程。受け取るのは出力ルートとコンパイル時カタログと対象の一覧、
//! 返すのは焼き直しの勘定であり、実行時カタログへの登録もここで行う。
//! 対象1件を焼く手順は`bake_one`が、据え置いた対象の項目を前回のカタログから写す手順は`carried_entry`が持つ。
//!
//! 増分の鍵にソース依存の一式を使うのは、チャンク1つが読む材料が1つとは限らないためである。前回の焼き上がりが
//! 何を読んだかは前回のカタログの依存一覧に残っており、その全部が変わっていなければ焼き直す理由が無い。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

mod bake_one;
mod carried_entry;

use std::path::Path;

use blitz_asset_compiler::{
    ソース依存一式の内容ハッシュを求める, チャンクの焼き直し判定, テクスチャ格納方針, 焼き直しの勘定, 生成台帳, 生成台帳の見出し, 種の由来,
};
use blitz_engine::カタログ;

use super::catalog::コンパイル対象;

/// その対象を増分の台帳で据え置ける単位として扱うかどうか。チャンク世界のチャンクだけが座標で台帳へ記録できる。
/// 世界に1つ据えるアセットは所有チャンクが原点で揃って座標では区別できないため、毎回焼く。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 台帳での扱い {
    チャンクとして記録する,
    毎回焼く,
}

pub(super) fn 台帳を見ながら対象一覧を焼く(
    出力ルート: &Path,
    コンパイル時カタログ: &カタログ,
    対象一覧: &[コンパイル対象],
    方針: テクスチャ格納方針,
    実行時カタログ: &mut カタログ,
) -> Result<焼き直しの勘定, String> {
    let 見出し = 生成台帳の見出し::実行中の生成器から作る(種の由来::種を持たない).map_err(|誤り| 誤り.to_string())?;
    let 前回の台帳 = 生成台帳::出力ルートから読み込む(出力ルート, 見出し).map_err(|誤り| 誤り.to_string())?;
    let 前回のカタログ = carried_entry::前回の実行時カタログを読む(出力ルート);
    let mut 今回の台帳 = 生成台帳::見出しを与えて空を作る(見出し);
    let mut 判定一覧 = Vec::new();
    for 対象 in 対象一覧 {
        let 判定 = 対象1件の焼き直しを判定する(対象, &前回の台帳, 前回のカタログ.as_ref())?;
        match 判定 {
            Some(チャンクの焼き直し判定::据え置く { 内容ハッシュ }) => {
                carried_entry::前回の項目を写す(対象, 前回のカタログ.as_ref(), 実行時カタログ)?;
                今回の台帳.内容ハッシュを記録する(対象.所有チャンク, 内容ハッシュ);
            }
            Some(チャンクの焼き直し判定::焼き直す) => {
                let 内容ハッシュ = bake_one::対象を焼いて登録する(コンパイル時カタログ, 対象, 方針, 実行時カタログ)?;
                今回の台帳.内容ハッシュを記録する(対象.所有チャンク, 内容ハッシュ);
            }
            None => {
                bake_one::対象を焼いて登録する(コンパイル時カタログ, 対象, 方針, 実行時カタログ)?;
            }
        }
        判定一覧.extend(判定);
    }
    今回の台帳.出力ルートへ書き出す(出力ルート).map_err(|誤り| 誤り.to_string())?;
    Ok(焼き直しの勘定::判定の一覧から数える(判定一覧.into_iter()))
}

/// 台帳が扱わない対象では値なしを返す。値なしと「焼き直す」を分けるのは、勘定がチャンクの本数だけを数えるためである。
fn 対象1件の焼き直しを判定する(
    対象: &コンパイル対象,
    前回の台帳: &生成台帳,
    前回のカタログ: Option<&カタログ>,
) -> Result<Option<チャンクの焼き直し判定>, String> {
    if 対象.台帳での扱い == 台帳での扱い::毎回焼く {
        return Ok(None);
    }
    let 今の内容ハッシュ = match carried_entry::前回の項目を参照する(対象, 前回のカタログ) {
        Some(項目) => Some(ソース依存一式の内容ハッシュを求める(項目.ソース依存一覧()).map_err(|誤り| 誤り.to_string())?),
        None => None,
    };
    Ok(Some(前回の台帳.チャンクを焼き直すかを判定する(
        対象.所有チャンク,
        今の内容ハッシュ,
        &対象.出力パス,
    )))
}
