//! 世界全体を覆う遠景地形を焼き、通常シーンとして登録する工程。

use blitz_asset_compiler::{チャンクの高さ格子ソース, 遠景アセットをコンパイルする};
use blitz_engine::height_field::世界の遠景地形の安定IDの綴り;
use blitz_engine::アセットID;

use super::compilation::実行時アセットのコンパイル;

/// セルごとの実測最大偏差が地形規模を受け持つため、安全幅は数値誤差だけを覆う。逆向き深度の遠方誤差はmm未満であり、
/// 0.10mは2桁の余裕を持ちながら継ぎ目の見た目へ影響する大きさより1桁小さい。
const 安全幅メートル: f32 = 0.10;

impl 実行時アセットのコンパイル {
    pub(super) fn 遠景地形を焼いて登録する(&mut self, ソース一覧: &[チャンクの高さ格子ソース]) -> Result<(), String> {
        let id = アセットID::生成する(世界の遠景地形の安定IDの綴り).map_err(|誤り| 誤り.to_string())?;
        let 結果 = 遠景アセットをコンパイルする(ソース一覧, 安全幅メートル).map_err(|誤り| format!("{id}: {誤り}"))?;
        println!(
            "[compile_assets] {} 頂点数={} インデックス数={}",
            結果.沈み統計.報告の行を作る(),
            結果.シーン.メタデータ.頂点数,
            結果.シーン.メタデータ.インデックス数
        );
        let 実行時パス = self
            .出力ルート
            .アセットを書き出す(&id, &結果.シーン.実行時バイト列)
            .map_err(|誤り| 誤り.to_string())?;
        self.実行時カタログ
            .詳細を登録する(id, 実行時パス, 結果.シーン.ソース依存一覧, 結果.シーン.メタデータ);
        Ok(())
    }
}
