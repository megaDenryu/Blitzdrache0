//! 個体数の勘定: 焼き上がった実行時カタログが持つ個体数を数え上げ、報告の行を組み立てる型。
//!
//! 散布が効いていることは生成物の中身を見ても分からない。チャンクのファイルは散布があってもなくても
//! 同じ拡張子の同じ形式であり、増分が効いたかを焼き直した本数でしか見られないのと同じ事情である。
//! したがって個体数の合計が、散布が効いたことの唯一の証拠になる。
//!
//! 数え上げの材料を実行時カタログにするのは、据え置いたチャンクでも正しい数が出るためである。
//! 焼く工程が数えた数を持ち回ると、据え置いたチャンクの個体を数え落として、増分が効いた実行だけ合計が減る。
//! 据え置きの項目は前回のカタログから写されており、容量メタデータの個体数もそのまま写っている。
//!
//! 注意: 報告の行の綴りは`xtask/src/game_fox_tour/map_generation_check/instance_tally.rs`が読み取る側として
//! 同じものを持つ。食い違えば検収が合計を読めずに失敗する。両側にあることは`cargo xtask conform`の
//! 綴りの契約の検査が守る。

use blitz_engine::カタログ;

/// 個体数の合計と、個体を持つ対象の数。1つの数だけでは、1つの対象が全部を持つ形と多くの対象が分け合う形を
/// 見分けられない。散布はチャンクごとに群を作るため、対象の数が常駐の描画発行数の見込みにそのまま効く。
pub(super) struct 個体数の勘定 {
    合計: u64,
    個体を持つ対象数: usize,
}

impl 個体数の勘定 {
    pub(super) fn 実行時カタログから数える(カタログ: &カタログ) -> Self {
        let mut 合計 = 0_u64;
        let mut 個体を持つ対象数 = 0_usize;
        for (_, 項目) in カタログ.全項目を走査する() {
            let 個体数 = 項目.メタデータ().個体数;
            if 個体数 > 0 {
                個体を持つ対象数 += 1;
                合計 = 合計.saturating_add(個体数);
            }
        }
        Self {
            合計, 個体を持つ対象数
        }
    }

    pub(super) fn 報告の行を作る(&self) -> String {
        format!("個体数の合計={} 個体を持つ対象数={}", self.合計, self.個体を持つ対象数)
    }
}
