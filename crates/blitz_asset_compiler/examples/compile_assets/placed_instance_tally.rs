//! 置いた個体の勘定: 焼く工程が実際に置いた個体を数え上げ、報告の行を組み立てる型。
//!
//! 実行時カタログのメタデータから数える`個体数の勘定`と別に持つのは、2つが同じ1つの計算から出ると突き合わせが
//! 自分自身との比べになるためである。こちらが数えるのは、配置列がインスタンス群になる直前で数えた値を焼いた対象ごとに
//! 積み上げたものであり、群の描画対象がシーンへ載らなかった欠陥は2つの数の食い違いとして現れる。
//!
//! 据え置いた対象は焼く工程を通らないため0体として積み上がる。したがって2つの数の一致を課してよいのは、
//! 据え置いたチャンクが0本の実行だけである。この前提は検収の側が焼き直しの報告の行を読んで確かめる。
//!
//! 注意: 報告の行の綴りは`xtask/src/game_fox_tour/map_generation_check/compile_report.rs`が読み取る側として
//! 同じものを持つ。両側にあることは`cargo xtask conform`の綴りの契約の検査が守る。

use blitz_asset_compiler::置いた個体の数;

pub(super) struct 置いた個体の勘定 {
    合計: 置いた個体の数,
}

impl 置いた個体の勘定 {
    pub(super) fn 零から始める() -> Self {
        Self {
            合計: 置いた個体の数::零()
        }
    }

    pub(super) fn 足す(&mut self, 数: 置いた個体の数) -> Result<(), String> {
        self.合計 = self.合計.足す(数).map_err(|誤り| 誤り.to_string())?;
        Ok(())
    }

    pub(super) fn 報告の行を作る(&self) -> String {
        format!("置いた個体の合計={}", self.合計.値())
    }
}
