//! 起動引数から「どの世界をどこからどこへ焼くか」を読む工程。受け取るのは引数の並び、返すのは焼く世界の指定である。
//!
//! 解析の結果を1つの型で返すのは、位置引数の並びの意味を呼び出し側が覚えないためである。
//! テクスチャ格納方針の綴りの解析は`texture_policy_argument`が持つ。

use std::path::PathBuf;

use blitz_asset_compiler::{
    ソースルート, テクスチャ格納方針, 対象世界, 散布の焼き方, 焼く世界の指定, 遠景地形の焼き方
};

use super::texture_policy_argument;

/// この入口が当てはめる既定のテクスチャ格納方針。既定を当てはめるのはこの1箇所だけであり、
/// コンパイルのライブラリ関数は方針を必須の引数で受け取る。ブロック圧縮を渡すのは`cargo xtask texture-compression`だけである
/// (参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`「判断i」)。
const 既定のテクスチャ格納方針: テクスチャ格納方針 = テクスチャ格納方針::全てRGBA8;

pub(super) fn 引数一覧から焼く世界の指定を読む(全引数一覧: &[String]) -> Result<焼く世界の指定, String> {
    let (遠景地形, 遠景を除いた引数一覧) = 遠景地形の焼き方::引数一覧から取り出す(全引数一覧);
    let (散布, 散布を除いた引数一覧) = 散布の焼き方::引数一覧から取り出す(&遠景を除いた引数一覧);
    let (指定された方針, 引数一覧) = texture_policy_argument::引数一覧から方針の指定を取り出す(&散布を除いた引数一覧)?;
    let (ソースルート文字列, 出力ルート文字列, 世界名, 同居植生個体数) = match 引数一覧.as_slice() {
        [ソース, 出力, 世界名] => (ソース, 出力, 世界名, 対象世界::同居植生の既定個体数()),
        [ソース, 出力, 世界名, 個体数] => (ソース, 出力, 世界名, 同居植生個体数を解析する(個体数)?),
        _ => return Err("内部呼出しにはソースルートと出力ルートと世界名の3引数が必要である(第4引数は同居植生の個体数)".to_string()),
    };
    Ok(焼く世界の指定::組み立てを始める(
        ソースルート::生成する(PathBuf::from(ソースルート文字列)),
        PathBuf::from(出力ルート文字列),
        対象世界::引数名から解析する(世界名)?,
        世界名.clone(),
    )
    .焼き方を確定する(同居植生個体数, 指定された方針.unwrap_or(既定のテクスチャ格納方針), 遠景地形, 散布))
}

/// 同居植生の個体数。0はインスタンス群を持てない値であり、コンパイラの奥まで運ぶより入口で拒む。
fn 同居植生個体数を解析する(引数: &str) -> Result<usize, String> {
    match 引数.parse::<usize>() {
        Ok(個体数) if 個体数 > 0 => Ok(個体数),
        Ok(_) => Err("同居植生の個体数は1以上である必要がある".to_string()),
        Err(誤り) => Err(format!("同居植生の個体数を数として読めない: {誤り}")),
    }
}
