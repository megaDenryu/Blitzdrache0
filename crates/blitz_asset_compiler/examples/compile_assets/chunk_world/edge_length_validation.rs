//! 目録が世界ごとに宣言した一辺と、全高さ格子が複製した一辺との一致を焼く前に確かめる。

use blitz_asset_compiler::{アセットコンパイルエラー, チャンクの高さ格子ソース};
use blitz_engine::チャンク一辺;

pub(super) fn 目録と高さ格子の一辺が一致することを確かめる(
    目録の一辺: チャンク一辺,
    ソース一覧: &[チャンクの高さ格子ソース],
) -> Result<(), アセットコンパイルエラー> {
    for ソース in ソース一覧 {
        let 高さ格子 = ソース.読み込む()?;
        let 高さ格子の一辺 = 高さ格子.格子().諸元().一辺メートル();
        if 目録の一辺.f32値() != 高さ格子の一辺 {
            let 座標 = ソース.座標();
            return Err(アセットコンパイルエラー::チャンク一辺不一致 {
                目録: 目録の一辺.f32値(),
                高さ格子: 高さ格子の一辺,
                x: 座標.x(),
                z: 座標.z(),
            });
        }
    }
    Ok(())
}
