//! コンパイル対象1件を、据え置きの判定から仕上がりまで処理する工程。受け取るのはコンパイル時カタログと対象と
//! 前回の台帳と前回のカタログ、返すのは実行時カタログへ登録する材料と、勘定へ渡す判定である。
//!
//! 実行時カタログへの登録をここで行わないのは、この工程を複数のチャンクで同時に走らせるためである。
//! 登録は呼び出し側が対象の並びの順で行い、並列に走らせても結果が同じになるようにする。

use std::path::PathBuf;

use blitz_asset_compiler::{
    ソース依存一式の内容ハッシュを求める, チャンクの焼き直し判定, テクスチャ格納方針, 内容ハッシュ, 生成台帳
};
use blitz_engine::{アセットメタデータ, カタログ};

use super::super::catalog::コンパイル対象;
use super::{bake_one, carried_entry, 台帳での扱い};

/// 対象1件の仕上がり。実行時カタログの項目3つと、台帳へ記録する内容ハッシュと、勘定へ渡す判定を持つ。
pub(super) struct 対象1件の仕上がり {
    pub(super) 実行時パス: PathBuf,
    pub(super) ソース依存一覧: Vec<PathBuf>,
    pub(super) メタデータ: アセットメタデータ,
    /// 台帳が扱わない対象では値なしである。世界に1つ据えるアセットは所有チャンクが原点で揃うため、
    /// 記録すると原点のチャンクの記録を上書きしてしまう。
    pub(super) 台帳へ記録する内容ハッシュ: Option<内容ハッシュ>,
    pub(super) 焼き直しの判定: Option<チャンクの焼き直し判定>,
}

pub(super) fn 対象1件を仕上げる(
    コンパイル時カタログ: &カタログ,
    対象: &コンパイル対象,
    方針: テクスチャ格納方針,
    前回の台帳: &生成台帳,
    前回のカタログ: Option<&カタログ>,
) -> Result<対象1件の仕上がり, String> {
    let 判定 = 焼き直しを判定する(対象, 前回の台帳, 前回のカタログ)?;
    if let Some(チャンクの焼き直し判定::据え置く { 内容ハッシュ }) = 判定 {
        return carried_entry::前回の項目を写す(対象, 前回のカタログ, 内容ハッシュ);
    }
    let 焼き上がり = bake_one::対象を焼いて書き出す(コンパイル時カタログ, 対象, 方針)?;
    Ok(対象1件の仕上がり {
        実行時パス: 焼き上がり.実行時パス,
        ソース依存一覧: 焼き上がり.ソース依存一覧,
        メタデータ: 焼き上がり.メタデータ,
        台帳へ記録する内容ハッシュ: 判定.map(|_| 焼き上がり.内容ハッシュ),
        焼き直しの判定: 判定,
    })
}

/// 台帳が扱わない対象では値なしを返す。値なしと「焼き直す」を分けるのは、勘定がチャンクの本数だけを数えるためである。
fn 焼き直しを判定する(
    対象: &コンパイル対象,
    前回の台帳: &生成台帳,
    前回のカタログ: Option<&カタログ>,
) -> Result<Option<チャンクの焼き直し判定>, String> {
    if 対象.台帳での扱い == 台帳での扱い::毎回焼く {
        return Ok(None);
    }
    let 今の内容ハッシュ = match carried_entry::前回の項目を参照する(対象, 前回のカタログ) {
        Some(項目) => Some(ソース依存一式の内容ハッシュを求める(項目.ソース依存一覧()).map_err(|誤り| 誤り.to_string())?),
        None => None,
    };
    Ok(Some(前回の台帳.チャンクを焼き直すかを判定する(
        対象.所有チャンク,
        今の内容ハッシュ,
        &対象.出力パス,
    )))
}
