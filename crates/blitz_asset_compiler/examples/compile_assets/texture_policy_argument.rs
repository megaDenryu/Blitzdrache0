//! プロセス境界でテクスチャ格納方針を指す綴りの台帳と、引数一覧からその指定を取り出す解析。
//! 綴りはxtask側(`xtask/src/compile_assets/texture_policy_name.rs`)にも同じものがあり、2つの実行ファイルの
//! 引数の受け渡しがこの綴りで一致していることを、知らない綴りを失敗にすることで確かめる。
//!
//! 指定を位置引数でなく選択肢の綴りで受けるのは、既にある位置引数(ソースルート・出力ルート・世界名・同居植生個体数)の
//! どれとも紛れないようにするためである。指定が無いときの既定を当てはめるのは呼び出し元の`main`1箇所だけである。

use blitz_asset_compiler::テクスチャ格納方針;

/// 方針の指定を導く選択肢の綴り。この綴りの直後の1語が方針の名前である。
const 選択肢の綴り: &str = "--texture-storage-policy";

const 全てRGBA8の綴り: &str = "all_rgba8";
const ベースカラーのブロック圧縮の綴り: &str = "block_compressed_base_color";

const 有効な綴り: [&str; 2] = [全てRGBA8の綴り, ベースカラーのブロック圧縮の綴り];

/// 引数一覧から方針の指定を取り除き、指定があればその方針と残りの引数を返す。
pub(super) fn 引数一覧から方針の指定を取り出す(
    引数一覧: &[String],
) -> Result<(Option<テクスチャ格納方針>, Vec<String>), String> {
    let Some(選択肢の位置) = 引数一覧.iter().position(|引数| 引数 == 選択肢の綴り) else {
        return Ok((None, 引数一覧.to_vec()));
    };
    let 名前 = 引数一覧
        .get(選択肢の位置 + 1)
        .ok_or_else(|| format!("{選択肢の綴り}の直後に方針の名前が無い(有効な値は{})", 有効な綴り.join("と")))?;
    let 方針 = 名前からテクスチャ格納方針を解析する(名前)?;
    let mut 残り = 引数一覧[..選択肢の位置].to_vec();
    残り.extend_from_slice(&引数一覧[選択肢の位置 + 2..]);
    Ok((Some(方針), 残り))
}

fn 名前からテクスチャ格納方針を解析する(名前: &str) -> Result<テクスチャ格納方針, String> {
    match 名前 {
        全てRGBA8の綴り => Ok(テクスチャ格納方針::全てRGBA8),
        ベースカラーのブロック圧縮の綴り => Ok(テクスチャ格納方針::ベースカラーのブロック圧縮),
        他 => Err(format!("未知のテクスチャ格納方針である: {他}(有効な値は{})", 有効な綴り.join("と"))),
    }
}
