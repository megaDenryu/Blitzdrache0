//! 実行時アセットのコンパイル: 1回の実行が焼く1つの世界について、置き場と方針とカタログを保持するサービス型。
//! 焼く工程はこの型のメソッドであり、置き場や実行時カタログを引数で持ち回る自由関数の連鎖にしない。
//!
//! 依存を保持させるのは、ソースルート・出力ルート・世界・焼き方・2つのカタログが、1回のコンパイルの間ずっと
//! 持ち回る状態だからである。引数で渡し歩くと、どの工程がどの状態を触れるかが署名からは分からなくなり、
//! 取り違えても型が通る。工程ごとの中身は、宣言の取り込みが`catalog`、チャンクの取り込みと目録が`chunk_world`、
//! 増分の台帳が`chunk_ledger`、高さ場が`height_field`にある。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

use blitz_asset_compiler::{
    ソースアセットのコンパイル係, ソースルート, テクスチャ格納方針, 実行時形式の出力ルート
};
use blitz_engine::{カタログ, カタログを実行時形式へ格納する};

use super::arguments::焼く世界の指定;
use super::chunk_ledger::焼き方の指定;
use super::world::対象世界;

pub(super) struct 実行時アセットのコンパイル {
    pub(super) ソースルート: ソースルート,
    pub(super) 出力ルート: 実行時形式の出力ルート,
    pub(super) 世界: 対象世界,
    pub(super) 世界名: String,
    pub(super) 同居植生個体数: usize,
    pub(super) テクスチャ格納方針: テクスチャ格納方針,
    /// ソースの置き場を安定IDから引くためのカタログ。焼く工程が材料を開くのに使う。
    pub(super) コンパイル時カタログ: カタログ,
    /// 焼き上がりを載せていくカタログ。出力ルートへ書き出すのはこの1つである。
    pub(super) 実行時カタログ: カタログ,
}

impl 実行時アセットのコンパイル {
    pub(super) fn 始める(指定: 焼く世界の指定) -> Result<Self, String> {
        Ok(Self {
            ソースルート: 指定.ソースルート,
            出力ルート: 実行時形式の出力ルート::作る(指定.出力ルートのパス).map_err(|誤り| 誤り.to_string())?,
            世界: 指定.世界,
            世界名: 指定.世界名,
            同居植生個体数: 指定.同居植生個体数,
            テクスチャ格納方針: 指定.テクスチャ格納方針,
            コンパイル時カタログ: カタログ::空を作る(),
            実行時カタログ: カタログ::空を作る(),
        })
    }

    pub(super) fn 世界を焼く(mut self) -> Result<(), String> {
        let mut 対象一覧 = self.アセット宣言をカタログへ写す()?;
        let 取り込み結果 = self.チャンク世界を取り込む(&mut 対象一覧)?;
        self.縁の一致を確かめる(&取り込み結果)?;
        let 焼き上がり = self.台帳を見ながら対象一覧を焼く(&対象一覧)?;
        println!("[compile_assets] {}", 焼き上がり.勘定.報告の行を作る());
        if self.世界.高さ場を焼くか() {
            self.高さ場を焼いて登録する(&取り込み結果.チャンクごとのソース一覧)?;
        }
        self.実行時カタログを書き出す()?;
        self.チャンク目録を書き出す(&取り込み結果.目録)?;
        // 注意: 生成台帳は出力一式の最後に確定させる。ここより前で確定させると、カタログか目録の書き出しに失敗した実行が
        // 「新しい台帳と古いカタログ」を残し、次の実行がチャンクを据え置きながら古いカタログの項目を写して食い違う。
        焼き上がり
            .書き出しを待つ生成台帳
            .出力ルートへ書き出す(self.出力ルート.台帳の置き場())
            .map_err(|誤り| 誤り.to_string())
    }

    /// 焼く工程が使う係を、自分が保持するコンパイル時カタログと格納方針から組む。ここが依存の配線の1箇所である。
    pub(super) fn ソースアセットのコンパイル係を作る(&self) -> ソースアセットのコンパイル係<'_> {
        ソースアセットのコンパイル係::生成する(&self.コンパイル時カタログ, self.テクスチャ格納方針)
    }

    /// 材料が同じでも生成物を変える指定。増分の鍵の見出しへ入れるため、この型が保持する指定から組む。
    pub(super) fn 焼き方の指定を作る(&self) -> 焼き方の指定<'_> {
        焼き方の指定 {
            世界名: &self.世界名,
            同居植生個体数: self.同居植生個体数,
            テクスチャ格納方針: self.テクスチャ格納方針,
        }
    }

    fn 実行時カタログを書き出す(&self) -> Result<(), String> {
        let バイト列 = カタログを実行時形式へ格納する(&self.実行時カタログ).map_err(|誤り| 誤り.to_string())?;
        self.出力ルート.実行時カタログを書き出す(&バイト列).map_err(|誤り| 誤り.to_string())
    }
}
