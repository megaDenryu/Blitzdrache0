//! どのソース種別の地面が高さ格子で書かれているかの台帳。担当するのはその1つの引き当てだけである。
//!
//! 台帳を親から分けるのは、ソース種別が増えるたびにこの一覧だけが伸び、種別の定義そのものと押し合うためである。
//! `world`の側で目録ソースの置き場・チャンクのソース形式・散布の宣言をそれぞれ別の台帳へ分けているのと同じ分け方である。
//!
//! 網羅的matchで書くのは、地面を持つ種別を1つ足したときに、この台帳へ書き足すまでコンパイルが通らないようにするためである。
//! ワイルドカードの枝を置くと、新しい種別が黙って「高さ格子でない」側へ倒れ、縁の一致の検査が空振りする。

use super::ソース種別;

impl ソース種別 {
    /// そのチャンクの地面が高さ格子で書かれているか。縁の一致の検査は高さ格子のチャンクだけを対象にする。
    /// 地面の上に何を載せるかは種別ごとに違っても、縁が一致していなければならない点は同じである。
    pub(crate) fn 地面が高さ格子で書かれているか(self) -> bool {
        match self {
            Self::高さ格子 { .. }
            | Self::固定物を据えた高さ格子 { .. }
            | Self::見本の集落 { .. }
            | Self::部品で建てた家並み(_)
            | Self::目視見本 { .. } => true,
            Self::Gltfシーン
            | Self::寸法を合わせるGltfシーン { .. }
            | Self::植生 { .. }
            | Self::植生可視判定
            | Self::植生単一個体
            | Self::植生影視距離
            | Self::植生詳細段 => false,
        }
    }
}
