//! コンパイル対象1件を、ソース種別に応じたコンパイル工程へ振り分ける割り当て。受け取るのはカタログと対象、
//! 返すのは実行時バイト列と依存とメタデータの組である。
//!
//! 割り当てを`main`から分けるのは、ソース種別が増えるたびに引数の解析と生成物の書き出しが同じファイルで押し合うためである。
//! 宣言をコンパイラが受け取る指定へ写す手順は、写しが種別ごとに違うためこのモジュールが持つ。

use blitz_asset_compiler::{
    コンパイル済みシーン, ソースシーンをコンパイルする, テクスチャ格納方針, 同居植生の指定, 地形チャンクをコンパイルする,
    植生チャンクをコンパイルする, 植生単一個体シーンをコンパイルする, 植生可視判定シーンをコンパイルする, 植生影視距離シーンをコンパイルする,
    植生詳細段シーンをコンパイルする, 目視見本チャンクをコンパイルする, 見本の集落チャンクをコンパイルする,
};
use blitz_engine::{アセットID, カタログ};

use super::catalog::{コンパイル対象, ソース種別};
use super::world::prop_group_declaration::群の指定一覧を作る;
use super::world::visual_sample_declaration::目視見本の指定を作る;

pub(super) fn 対象をコンパイルする(
    カタログ: &カタログ,
    対象: &コンパイル対象,
    方針: テクスチャ格納方針,
) -> Result<コンパイル済みシーン, String> {
    let 結果 = match 対象.種別 {
        ソース種別::Gltfシーン => ソースシーンをコンパイルする(カタログ, &対象.id, 対象.所有チャンク, 方針),
        ソース種別::高さ格子 { 同居植生 } => {
            let 指定 = 同居植生.map(同居植生の指定へ写す).transpose()?;
            地形チャンクをコンパイルする(カタログ, &対象.id, 対象.所有チャンク, 指定.as_ref(), 方針)
        }
        ソース種別::植生 { 個体数 } => 植生チャンクをコンパイルする(カタログ, &対象.id, 対象.所有チャンク, 個体数, 方針),
        ソース種別::植生可視判定 => 植生可視判定シーンをコンパイルする(カタログ, &対象.id, 対象.所有チャンク, 方針),
        ソース種別::植生単一個体 => 植生単一個体シーンをコンパイルする(カタログ, &対象.id, 対象.所有チャンク, 方針),
        ソース種別::植生影視距離 => 植生影視距離シーンをコンパイルする(カタログ, &対象.id, 対象.所有チャンク, 方針),
        ソース種別::植生詳細段 => 植生詳細段シーンをコンパイルする(カタログ, &対象.id, 対象.所有チャンク, 方針),
        ソース種別::見本の集落 { 群一覧 } => {
            let 指定一覧 = 群の指定一覧を作る(群一覧)?;
            見本の集落チャンクをコンパイルする(カタログ, &対象.id, 対象.所有チャンク, &指定一覧, 方針)
        }
        ソース種別::目視見本 {
            材質見本の立体の安定id,
            遠景地面の安定id,
            群一覧,
        } => {
            let 指定 = 目視見本の指定を作る(材質見本の立体の安定id, 遠景地面の安定id, 群一覧)?;
            目視見本チャンクをコンパイルする(カタログ, &対象.id, 対象.所有チャンク, &指定, 方針)
        }
    };
    結果.map_err(|誤り| format!("{}: {誤り}", 対象.id))
}

/// 宣言が持つ安定IDの綴りを検証済みのアセットIDへ写す。宣言側が`Copy`のまま安定IDを綴りで持つのは、
/// `ソース種別`を`Copy`に保つためである。
fn 同居植生の指定へ写す(宣言: super::catalog::同居植生宣言) -> Result<同居植生の指定, String> {
    Ok(同居植生の指定 {
        原型id: アセットID::生成する(宣言.原型の安定id).map_err(|誤り| 誤り.to_string())?,
        個体数: 宣言.個体数,
    })
}
