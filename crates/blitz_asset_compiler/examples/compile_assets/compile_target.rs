//! コンパイル対象1件を、ソース種別に応じたコンパイル工程へ振り分ける割り当て。受け取るのは対象、
//! 返すのは実行時バイト列と依存とメタデータの組である。コンパイル係は対象1件の仕上げ係が保持している。
//!
//! 対象1件の型は`entry`が持つ。
//!
//! 割り当てを`main`から分けるのは、ソース種別が増えるたびに引数の解析と生成物の書き出しが同じファイルで押し合うためである。
//! 宣言をコンパイラが受け取る指定へ写す手順は、写しが種別ごとに違うためこのモジュールが持つ。

mod entry;

use blitz_asset_compiler::{コンパイル済みシーン, 同居植生の指定, 寸法を合わせる一様倍率};
use blitz_engine::アセットID;

pub(crate) use entry::コンパイル対象;

use super::chunk_ledger::対象1件の仕上げ係;
use super::source_kind::ソース種別;
use super::world::assembled_scatter_declaration::部品で組む散布の指定一覧を作る;
use super::world::fixed_placement_declaration::据え付け一覧を作る;
use super::world::part_row_declaration::部品で組んだ並びの指定を作る;
use super::world::prop_group_declaration::原型と置き方の指定一覧を作る;
use super::world::visual_sample_declaration::目視見本の指定を作る;

impl 対象1件の仕上げ係<'_> {
    pub(crate) fn 対象をコンパイルする(&self, 対象: &コンパイル対象) -> Result<コンパイル済みシーン, String> {
        let コンパイル係 = self.コンパイル係;
        let id = &対象.id;
        let 所有チャンク = 対象.所有チャンク;
        let 結果 = match 対象.種別 {
            ソース種別::Gltfシーン => コンパイル係.ソースシーンをコンパイルする(id, 所有チャンク),
            ソース種別::寸法を合わせるGltfシーン { 一様倍率 } => {
                let 倍率 = 寸法を合わせる一様倍率::生成する(一様倍率).map_err(|誤り| 誤り.to_string())?;
                コンパイル係.寸法を合わせる倍率を与えてソースシーンをコンパイルする(id, 所有チャンク, 倍率)
            }
            ソース種別::高さ格子 { 同居植生 } => {
                let 指定 = 同居植生.map(同居植生の指定へ写す).transpose()?;
                コンパイル係.地形チャンクをコンパイルする(id, 所有チャンク, 指定.as_ref())
            }
            ソース種別::植生 { 個体数 } => コンパイル係.植生チャンクをコンパイルする(id, 所有チャンク, 個体数),
            ソース種別::植生可視判定 => コンパイル係.植生可視判定シーンをコンパイルする(id, 所有チャンク),
            ソース種別::植生単一個体 => コンパイル係.植生単一個体シーンをコンパイルする(id, 所有チャンク),
            ソース種別::植生影視距離 => コンパイル係.植生影視距離シーンをコンパイルする(id, 所有チャンク),
            ソース種別::植生詳細段 => コンパイル係.植生詳細段シーンをコンパイルする(id, 所有チャンク),
            ソース種別::見本の集落 { 群一覧 } => {
                let 指定一覧 = 原型と置き方の指定一覧を作る(群一覧)?;
                コンパイル係.見本の集落チャンクをコンパイルする(id, 所有チャンク, &指定一覧)
            }
            ソース種別::部品で組んだ並び(宣言) => {
                let 指定 = 部品で組んだ並びの指定を作る(宣言)?;
                コンパイル係.部品で組んだ並びのチャンクをコンパイルする(id, 所有チャンク, &指定)
            }
            ソース種別::固定物を据えた高さ格子 {
                据え付け一覧: 宣言一覧,
                散布一覧,
                部品で組む散布一覧,
            } => {
                let 据え付け一覧 = 据え付け一覧を作る(宣言一覧, 所有チャンク)?;
                let 散布の指定一覧 = 原型と置き方の指定一覧を作る(散布一覧)?;
                let 部品で組む散布の指定一覧 = 部品で組む散布の指定一覧を作る(部品で組む散布一覧)?;
                コンパイル係.固定物を据えた地形チャンクをコンパイルする(
                    id,
                    所有チャンク,
                    &据え付け一覧,
                    &散布の指定一覧,
                    &部品で組む散布の指定一覧,
                )
            }
            ソース種別::目視見本 {
                材質見本の立体の安定id,
                遠景地面の安定id,
                群一覧,
            } => {
                let 指定 = 目視見本の指定を作る(材質見本の立体の安定id, 遠景地面の安定id, 群一覧)?;
                コンパイル係.目視見本チャンクをコンパイルする(id, 所有チャンク, &指定)
            }
        };
        結果.map_err(|誤り| format!("{}: {誤り}", 対象.id))
    }
}

/// 宣言が持つ安定IDの綴りを検証済みのアセットIDへ写す。宣言側が`Copy`のまま安定IDを綴りで持つのは、
/// `ソース種別`を`Copy`に保つためである。
fn 同居植生の指定へ写す(宣言: super::catalog::同居植生宣言) -> Result<同居植生の指定, String> {
    Ok(同居植生の指定 {
        原型id: アセットID::生成する(宣言.原型の安定id).map_err(|誤り| 誤り.to_string())?,
        個体数: 宣言.個体数,
    })
}
