//! チャンク世界の取り込みと、実行時の版付きチャンク目録の書き出し。世界が宣言した目録ソースを読んでチャンクを
//! コンパイル対象へ加える。座標はソースの宣言だけを根拠にし、ファイル名から逆算しない。
//!
//! チャンクごとのソースパスを目録と一緒に返すのは、高さ場アセットと縁の一致の検査が同じ高さ格子をもう一度材料にするためである。
//! 目録ソースを2度読むと、2つの読み取りの間で座標とソースの対応が食い違いうる。
//!
//! 置き場と世界とカタログはコンパイルのサービス型が保持しているため、この工程は何も持参されない。

use std::path::PathBuf;

use blitz_asset_compiler::ソースの高さ格子の重なり帯が一致することを確かめる;
use blitz_engine::{チャンク座標, チャンク目録, チャンク目録を実行時形式へ格納する};

use super::chunk_ledger::台帳での扱い;
use super::compilation::実行時アセットのコンパイル;
use super::compile_target::コンパイル対象;

/// チャンク世界を取り込んだ結果。実行時の目録と、チャンクごとの高さ格子等のソースパスを持つ。
pub(super) struct チャンク世界の取り込み結果 {
    pub(super) 目録: チャンク目録,
    pub(super) チャンクごとのソース一覧: Vec<(チャンク座標, PathBuf)>,
}

impl 実行時アセットのコンパイル {
    pub(super) fn チャンク世界を取り込む(
        &mut self,
        対象一覧: &mut Vec<コンパイル対象>,
    ) -> Result<チャンク世界の取り込み結果, String> {
        let ディレクトリ名 = self.世界.世界のソースディレクトリ名().map_err(|誤り| 誤り.to_string())?;
        let 目録ソースの置き場 = self.ソースルート.世界のチャンク目録ソースの置き場(ディレクトリ名);
        let 項目一覧 = 目録ソースの置き場.目録の項目一覧を読み込む()?;
        let チャンクのソース種別 = self.世界.チャンクのソース種別(self.同居植生個体数);
        let mut 目録 = チャンク目録::空を作る();
        let mut チャンクごとのソース一覧 = Vec::with_capacity(項目一覧.len());
        for 項目 in 項目一覧 {
            let ソースパス = 目録ソースの置き場.目録が指すチャンクのソース(項目.ソース相対パス())?;
            目録
                .登録する(項目.チャンク(), 項目.アセット().clone())
                .map_err(|誤り| format!("{}: {誤り}", 目録ソースの置き場.目録ソースの表示の綴り()))?;
            self.コンパイル時カタログ.登録する(項目.アセット().clone(), ソースパス.clone());
            対象一覧.push(コンパイル対象::生成する(
                項目.アセット().clone(),
                項目.チャンク(),
                チャンクのソース種別,
                &self.出力ルート,
                台帳での扱い::チャンクとして記録する,
            ));
            チャンクごとのソース一覧.push((項目.チャンク(), ソースパス));
        }
        Ok(チャンク世界の取り込み結果 {
            目録,
            チャンクごとのソース一覧,
        })
    }

    /// 地面が高さ格子で書かれた世界では、チャンクを焼く前に隣り合うチャンクの重なり帯の一致を確かめる。
    /// チャンクを1つずつ独立に焼き直せるため、片方だけが新しくなって縁が食い違う状態がこの経路で起こりうる。
    pub(super) fn 縁の一致を確かめる(&self, 取り込み結果: &チャンク世界の取り込み結果) -> Result<(), String> {
        if !self.世界.チャンクのソース種別(self.同居植生個体数).地面が高さ格子で書かれているか() {
            return Ok(());
        }
        ソースの高さ格子の重なり帯が一致することを確かめる(&取り込み結果.チャンクごとのソース一覧).map_err(|誤り| 誤り.to_string())
    }

    pub(super) fn チャンク目録を書き出す(&self, 目録: &チャンク目録) -> Result<(), String> {
        let バイト列 = チャンク目録を実行時形式へ格納する(目録).map_err(|誤り| 誤り.to_string())?;
        self.出力ルート.チャンク目録を書き出す(&バイト列, 目録.件数())
    }
}
