//! チャンク世界の取り込み。世界が宣言した目録ソースを読んでチャンクをコンパイル対象へ加え、
//! 実行時の版付きチャンク目録を書き出す。座標はソースの宣言だけを根拠にし、ファイル名から逆算しない。
//!
//! チャンクごとのソースパスを目録と一緒に返すのは、高さ場アセットが同じ高さ格子をもう一度材料にするためである。
//! 目録ソースを2度読むと、2つの読み取りの間で座標とソースの対応が食い違いうる。

use std::path::PathBuf;

use blitz_engine::{カタログ, チャンク座標, チャンク目録, チャンク目録を実行時形式へ格納する};

use blitz_asset_compiler::{ソースルート, 実行時形式の出力ルート};

use super::chunk_ledger::台帳での扱い;
use super::compile_target::コンパイル対象;
use super::world::対象世界;

/// チャンク世界を取り込んだ結果。実行時の目録と、チャンクごとの高さ格子等のソースパスを持つ。
pub(super) struct チャンク世界の取り込み結果 {
    pub(super) 目録: チャンク目録,
    pub(super) チャンクごとのソース一覧: Vec<(チャンク座標, PathBuf)>,
}

pub(super) fn カタログへ登録する(
    ソースルート: &ソースルート,
    出力ルート: &実行時形式の出力ルート,
    世界: 対象世界,
    同居植生個体数: usize,
    カタログ: &mut カタログ,
    対象一覧: &mut Vec<コンパイル対象>,
) -> Result<チャンク世界の取り込み結果, String> {
    let 目録ソースの置き場 = ソースルート.世界のチャンク目録ソースの置き場(世界.世界のソースディレクトリ名());
    let 項目一覧 = 目録ソースの置き場.目録の項目一覧を読み込む()?;
    let mut 目録 = チャンク目録::空を作る();
    let mut チャンクごとのソース一覧 = Vec::new();
    for 項目 in 項目一覧 {
        let ソースパス = 目録ソースの置き場.目録が指すチャンクのソース(項目.ソース相対パス())?;
        目録
            .登録する(項目.チャンク(), 項目.アセット().clone())
            .map_err(|誤り| format!("{}: {誤り}", 目録ソースの置き場.目録ソースの表示の綴り()))?;
        カタログ.登録する(項目.アセット().clone(), ソースパス.clone());
        対象一覧.push(コンパイル対象::生成する(
            項目.アセット().clone(),
            項目.チャンク(),
            世界.チャンクのソース種別(同居植生個体数),
            出力ルート,
            台帳での扱い::チャンクとして記録する,
        ));
        チャンクごとのソース一覧.push((項目.チャンク(), ソースパス));
    }
    Ok(チャンク世界の取り込み結果 {
        目録,
        チャンクごとのソース一覧,
    })
}

pub(super) fn 目録を書き出す(出力ルート: &実行時形式の出力ルート, 目録: &チャンク目録) -> Result<(), String> {
    let バイト列 = チャンク目録を実行時形式へ格納する(目録).map_err(|誤り| 誤り.to_string())?;
    出力ルート.チャンク目録を書き出す(&バイト列, 目録.件数())
}
