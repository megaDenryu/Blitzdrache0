//! 部品の組み立て規則の種類と、種類から規則と展開の種の起点を組む引き当て。
//!
//! **並びと散布の両方がこの引き当てを使う。** どちらも「規則を1つ選んで、種で個体ごとに姿を変える」という
//! 同じ形であり、違うのは根をどこへ置くかだけである。宣言が規則そのものでなく種類を持つのは、
//! `ソース種別`を`Copy`のまま保つためである。組み立て規則は候補の並びを`Vec`で持つため`Copy`にできない。
//!
//! 規則そのものは種類ごとのモジュールが持つ。網羅的matchで書くため、種類を1つ足すと規則を書き足すまで通らない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「部品カタログと展開器」

mod frame_bay_choice;
mod frame_chain_rule;
mod frame_rule;
mod frame_wall_assignment;
mod house_rule;
mod part_list;
mod tree_rule;

use blitz_assembly::{生成の種, 組み立て規則};
use blitz_asset_compiler::散らした種類の名前;

use super::super::archetype_identity::原型の識別;

/// どの規則で1件を組むか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 部品の組み立て規則の種類 {
    酒場宿屋,
    樫の木,
    一間四方の骨格,
    /// 骨格を連ねた見本2つ。部品の一覧は1ベイ1段と同じであり、違うのは規則だけである。継いだ面には壁を入れない。
    二段に積んだ骨格,
    横に二ベイ継いだ骨格,
    /// 骨格の上へ切妻屋根を載せた家2つ。骨格ごとに床を1枚張り、部品の一覧に屋根が1件加わって6件になる。
    屋根を載せた一間四方の家,
    屋根を載せた二段の家,
}

impl 部品の組み立て規則の種類 {
    /// 報告の内訳へ載せるこの種類の名前。人が読んで何を散らしたのかが分かる語を使う。
    pub(super) fn 名前(self) -> 散らした種類の名前 {
        散らした種類の名前::綴りから生成する(match self {
            Self::酒場宿屋 => "酒場宿屋",
            Self::樫の木 => "樫の木",
            Self::一間四方の骨格 => "一間四方の骨格",
            Self::二段に積んだ骨格 => "二段に積んだ骨格",
            Self::横に二ベイ継いだ骨格 => "横に二ベイ継いだ骨格",
            Self::屋根を載せた一間四方の家 => "屋根を載せた一間四方の家",
            Self::屋根を載せた二段の家 => "屋根を載せた二段の家",
        })
    }

    /// その規則が指す部品の一覧。**規則と部品の一覧は常に対で使うため、種類が両方を答える。**
    /// 宣言の側が2つを別々に書くと、規則が指す部品を一覧へ書き忘れた宣言が型を通り、
    /// 「カタログに無い部品」という遠い場所の失敗になる。台帳は`part_list`が持つ。
    pub(super) fn 部品一覧(self) -> &'static [原型の識別] {
        part_list::部品一覧を選ぶ(self)
    }

    /// その種類の規則と、展開の種の起点を組む。
    pub(super) fn 規則と種の起点を組む(self) -> Result<(組み立て規則, 生成の種), String> {
        match self {
            Self::酒場宿屋 => Ok((house_rule::酒場宿屋の規則()?, house_rule::家の並びの展開の種())),
            Self::樫の木 => Ok((tree_rule::樫の木の規則()?, tree_rule::木の並びの展開の種())),
            Self::一間四方の骨格 => Ok((frame_rule::一間四方の骨格の規則を組む()?, frame_rule::一間四方の骨格の並びの展開の種())),
            Self::二段に積んだ骨格 => 骨格を連ねた規則へ種を添える(frame_chain_rule::二段に積んだ骨格の規則を組む()?),
            Self::横に二ベイ継いだ骨格 => 骨格を連ねた規則へ種を添える(frame_chain_rule::横に二ベイ継いだ骨格の規則を組む()?),
            Self::屋根を載せた一間四方の家 => {
                骨格を連ねた規則へ種を添える(frame_chain_rule::屋根を載せた一間四方の家の規則を組む()?)
            }
            Self::屋根を載せた二段の家 => 骨格を連ねた規則へ種を添える(frame_chain_rule::屋根を載せた二段の家の規則を組む()?),
        }
    }
}

/// 骨格を連ねた見本は1ベイ1段と同じ部品の同じはめ口から壁を引くため、展開の種の起点を共有する。
fn 骨格を連ねた規則へ種を添える(規則: 組み立て規則) -> Result<(組み立て規則, 生成の種), String> {
    Ok((規則, frame_rule::一間四方の骨格の並びの展開の種()))
}
