//! 対象世界のソースから生成台帳と実行時カタログへ渡す由来を読む。

use blitz_asset_compiler::{アセット配置エラー, ソースルート, 場所巡りの世界のソースディレクトリ, 種の由来};

use super::対象世界;

impl 対象世界 {
    pub(crate) fn 種の由来を読む(self, ソースルート: &ソースルート) -> Result<種の由来, アセット配置エラー> {
        if self != Self::場所巡りの世界 {
            return Ok(種の由来::種を持たない);
        }
        let 置き場 = 場所巡りの世界のソースディレクトリ::ソースルートの下を開く(ソースルート)?;
        Ok(種の由来::種から焼いた(置き場.生成に使った乱数の種を読む()?))
    }
}
