//! 屋内の多光源の検収世界が焼くものの宣言。担当するのは、平らな地面のチャンクへ据える石積みの小屋1棟の
//! 原型と据える位置を1箇所へ集めることだけである。
//!
//! 小屋を群でなく固定物として据えるのは、群の原型が全段で1つのマテリアルを共有する形式契約を持ち、
//! 石と木の2材質を持つこの小屋を受け取れないためである
//! (参照: `crates/blitz_asset_compiler/src/loader/archetype_material.rs`)。
//!
//! 据え付けは回転を持たないため、小屋は原型の姿勢のまま立つ。この原型の戸口は局所+Z軸を向いているため、
//! 戸口は世界の+Z軸を向き、カメラは小屋より+Z側に立って戸口ごしに屋内を見る
//! (`crates/blitz_app/src/app/scene_camera/stone_hut_doorway_view.rs`)。
//! 参照: `_doc/設計/Blenderアセット運用.md`「本体からの参照の仕組み」

use super::super::catalog::アセット定義;
use super::super::source_kind::{ソース種別, 固定物の据え付け宣言};
use super::definition_kind::外部ソース専用定義;

/// 小屋の原型。幅4.0・奥行3.0・高さ3.0メートルの、人が入れる大きさの石積みの小屋である。内部は空洞で戸口が1つ開いている。
const 小屋: (&str, &str) = ("stone_hut_interior_hut", "props/stone_hut.glb");

/// 小屋を据える大域の水平位置。一辺100メートルの原点チャンクの中央である。
const 小屋を据える位置: &[固定物の据え付け宣言] = &[固定物の据え付け宣言 {
    原型の安定id: 小屋.0,
    東メートル: 50,
    南メートル: 50,
}];

pub(super) fn チャンクのソース種別() -> ソース種別 {
    ソース種別::固定物を据えた高さ格子 {
        据え付け一覧: 小屋を据える位置,
    }
}

/// この世界がチャンク以外に焼くもの。小屋の原型はチャンクが素材として読むだけであり、実行時形式は作らない。
pub(super) fn 一覧() -> Vec<アセット定義> {
    vec![外部ソース専用定義(小屋.0, 小屋.1)]
}
