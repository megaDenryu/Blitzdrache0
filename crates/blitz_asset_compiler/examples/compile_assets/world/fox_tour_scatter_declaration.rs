///
/// どちらも急な面を好む。この世界の地形は緩く(傾きの中央値0.065・99パーセント点0.169)、傾きの下限を
/// 高く置くと1体も置かれない。小岩の下限0.05は中央値の少し下、大岩の下限0.09は中央値の上に取ってある。
/// 大岩を小岩より急な面へ限るのは、大きいものが転がり落ちて溜まる場所を選ぶためである。
///
/// 層のずらしを2種で変えるのは、同じ密度場を引くと小岩の多い所に必ず大岩も現れるためである。
