//! 場所巡りの世界が地面へ散らす原型の表。担当するのは、どの原型をどの密度でどんな面へ置くかを1箇所へ集めることだけである。
//! 密度場と傾きの好みの意味は`blitz_asset_compiler`の`密度場の散布`が持ち、宣言1件の組み立ては`prop_group_declaration`が持つ。
//!
//! 表を親から分けるのは、検査点3で木が加わるとこの表だけが伸び、世界の起動時シーンと目的地の宣言と押し合うためである。
//! 見本の集落の小物の表を`village_declaration`が持つのと同じ分け方である。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「判断j」

use blitz_asset_compiler::{傾きの好み, 地表への据え方};

use super::super::source_kind::原型と置き方の宣言;
use super::prop_group_declaration::密度で散らす;

/// 散らす岩2種と木1種の原型。実行時形式は焼かず、散布する地面のチャンクが素材として読むだけである。
pub(super) const 小岩: (&str, &str) = ("fox_tour_rock", "props/rock.glb");
pub(super) const 大岩: (&str, &str) = ("fox_tour_boulder", "props/boulder.glb");
pub(super) const 針葉樹: (&str, &str) = ("fox_tour_conifer", "props/conifer.glb");

/// 木と岩を分ける傾き。この値より緩い面には木だけが、急な面には岩だけが立つ。1つの値で分けるのは、
/// 第6段階の検査点3が「傾斜で木と岩を塗り分ける」ことを求めているためである。値は小岩の下限として
/// 検査点2で既に置かれたものをそのまま使い、新しい数を作らない。
const 木と岩を分ける傾き: f32 = 0.05;

/// 地面へ散らす岩2種と木1種。原型は外部のアセットリポジトリの`props/`から引く。
///
/// 走査の列数12は、一辺100メートルのチャンクを8.33メートルの区画144個へ分ける。実際に置かれる数は
/// 出現の割合と傾きの好みで減る。升目の標本数240は375メートルにあたり、高さの丘の層(96標本、150メートル)より
/// 広く取ってある。塊が数チャンクにまたがるためである。3種で同じ列数と同じ升目を使うのは、走査の格子と
/// 密度場の縮尺を世界で1つに保つためである。
///
/// 岩はどちらも急な面を好む。この世界の地形は緩く(傾きの中央値0.065・99パーセント点0.169)、傾きの下限を
/// 高く置くと1体も置かれない。小岩の下限0.05は中央値の少し下、大岩の下限0.09は中央値の上に取ってある。
/// 大岩を小岩より急な面へ限るのは、大きいものが転がり落ちて溜まる場所を選ぶためである。
///
/// 木は緩い面を好み、上限を小岩の下限と同じ値に置く。斜面に垂直に立つ木は不自然であり、また木と小岩が
/// 同じ面に混じると塗り分けが絵に出ないためである。出現の割合の下限を0にするのは、密度場の低い所を
/// 草原にするためである。上限を1でなく0.9にするのは、最も濃い森でも区画が埋まりきらず、走査の格子が
/// 絵に出ないようにするためである。大きさは若木から成木までの幅として取り、高さ5.6メートルの原型が
/// 4.5メートルから9.0メートルの範囲に散る。
///
/// 層のずらしを3種で変えるのは、同じ密度場を引くと小岩の多い所に必ず大岩も森も現れるためである。
///
/// 木の実測(2026-08-16、9チャンク)。走査の区画144個のうち傾きが上限以下なのは27.7パーセントである。
/// したがって1チャンクの木は、密度場の平均で17.9体、最も濃い森で35.9体、草原で0体になり、枠の64体の内側に収まる。
///
/// 注意: 3×3チャンクの地図は一辺300メートルであり、密度場の升目375メートルより小さい。密度場の値がほぼ1点しか
/// 取れないため、この地図は森か草原のどちらか一方になり、両方を1枚に収めることはできない。森と草原の対比が
/// 絵に出るのは大規模世界だけである。層のずらしを3×3の地図の見え方で選ぶことはしない。
