//! 固定物を据える宣言から、コンパイラが受け取る据え付けの一覧への写し。担当するのはこの写し1つだけであり、
//! どの世界がどの固定物をどこへ据えるかは宣言する側が持つ。
//!
//! 写しを世界ごとの宣言から分けるのは、大域の水平位置をチャンク座標と局所の位置へ分ける算術が世界に依らないためである。
//! 複数の世界がこの種別を使うため、写しを世界の側へ置くと同じ算術が世界の数だけ増える。

use blitz_asset_compiler::固定物の据え付け;
use blitz_engine::{アセットID, チャンク座標};

use super::super::source_kind::据える大域の水平位置;

/// チャンク1つの一辺。生成側の各世界(`crates/blitz_asset_compiler/examples/generate_source_assets/`)と同じ値である。
const チャンクの一辺メートル: i32 = 100;

/// そのチャンクへ据える固定物の一覧を作る。大域の水平位置をチャンク座標と局所の位置へ分け、
/// 所有チャンクに載るものだけを残す。1つも載らないチャンクは固定物を持たない地面だけのチャンクとして焼かれる。
pub(crate) fn 据え付け一覧を作る(
    固定物の原型の安定id: &str,
    位置一覧: &[据える大域の水平位置],
    所有チャンク: チャンク座標,
) -> Result<Vec<固定物の据え付け>, String> {
    let mut 一覧 = Vec::new();
    for 位置 in 位置一覧 {
        let (東のチャンク成分, 局所の東) = 大域メートルをチャンク成分と局所メートルへ分ける(位置.東メートル)?;
        let (南のチャンク成分, 局所の南) = 大域メートルをチャンク成分と局所メートルへ分ける(位置.南メートル)?;
        if 東のチャンク成分 != 所有チャンク.x() || 南のチャンク成分 != 所有チャンク.z() {
            continue;
        }
        一覧.push(固定物の据え付け {
            原型id: アセットID::生成する(固定物の原型の安定id).map_err(|誤り| 誤り.to_string())?,
            チャンク原点からの東メートル: 局所の東,
            チャンク原点からの南メートル: 局所の南,
        });
    }
    Ok(一覧)
}

/// 1つの軸について、大域のメートルをチャンク座標の成分とチャンク原点からの局所メートルへ分ける。
/// 負の大域位置もゼロ方向へ丸めず床を取るため、チャンク座標の求め方はストリーミングの格子と同じである。
fn 大域メートルをチャンク成分と局所メートルへ分ける(大域メートル: i32) -> Result<(i32, f32), String> {
    let 局所 = 大域メートル.rem_euclid(チャンクの一辺メートル);
    let 局所 = i16::try_from(局所).map_err(|_| format!("据える局所位置{局所}メートルが扱える範囲にない"))?;
    Ok((大域メートル.div_euclid(チャンクの一辺メートル), f32::from(局所)))
}
