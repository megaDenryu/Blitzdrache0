//! 樫の木の組み立て規則。幹を3節積んで上へ行くほど細くし、2節目の側面から枝を1本生やして、その先へ葉房を付ける。
//!
//! **細くなる比をどこにも書かない。** 幹頂部の直径0.4へ幹基部の直径0.5を継ぐと接合が0.8を導き、
//! 3節目ではその掛け合わせで0.64になる。規則が持つのは節の数と枝を出す節だけである。
//!
//! **枝が1本しか出ないのは、部品の宣言がそうなっているからである。** 幹の一節が持つ枝の生え口は1つだけであり、
//! その向きは節が変わっても同じである(接合面の姿勢が向きと上方向で完全に決まり、法線まわりに回す自由度が無い)。
//! したがって今の部品で組める木は、幹の途中から1方向へ枝が1本出た形が上限である。冠も無い。幹頂部が噛み合う
//! 相手は幹基部だけであり、葉房の根元は直径0.14の別の種別であるため、最上節の上は切り口のまま残る。
//! 部品の側へ生え口を方位違いで増やし、葉房へ幹基部の接合点を足す是正は`Blitzdrache0Assets`の担当である。
//! 参照: `_doc/設計/部品カタログと接合点.md`「木の実データが導いた倍率」

use blitz_assembly::{
    幹の指定, 幹の節数, 幹を下から数えた節の番号, 接合点名, 木の規則, 枝の指定, 生成の種, 組み立て規則, 葉房の指定, 部品ID
};

/// 木の並びの展開の種の起点。1件ごとにこの値から番号で分けた種を作る。値を固定するのは、同じ宣言から
/// 同じ配置を得るためである。木の規則は今のところ種から選ぶ余地を持たないため、この値は姿を変えない。
const 種の値: u64 = 0x5472_6565_526F_7700;

/// 幹を何節積むか。3節で丈が0から4.88メートルになる(2.0 + 2.0×0.8 + 2.0×0.64)。
const 幹の節数の値: usize = 3;

/// 枝を生やす節。根の節から出すと枝が地面へ近づきすぎ、最上節から出すと幹の切り口と枝が同じ高さに並ぶ。
const 枝を生やす節の番号: usize = 2;

pub(super) fn 木の並びの展開の種() -> 生成の種 {
    生成の種::値から生成する(種の値)
}

pub(super) fn 樫の木の規則() -> Result<組み立て規則, String> {
    let 規則 = 木の規則::生成する(
        幹の指定 {
            部品: 識別子("Mod_Tree_Oak_Trunk_Segment")?,
            基部: 名前("幹基部")?,
            頂部: 名前("幹頂部")?,
            枝の生え口: 名前("枝の生え口")?,
        },
        幹の節数::生成する(幹の節数の値).map_err(|誤り| 誤り.to_string())?,
        幹を下から数えた節の番号::生成する(枝を生やす節の番号).map_err(|誤り| 誤り.to_string())?,
        枝の指定 {
            部品: 識別子("Mod_Tree_Oak_Branch_Large")?,
            根元: 名前("枝の根元")?,
            頂芽: 名前("頂芽")?,
        },
        葉房の指定 {
            部品: 識別子("Mod_Tree_Oak_Foliage_Cluster")?,
            根元: 名前("葉房の根元")?,
        },
    )
    .map_err(|誤り| 誤り.to_string())?;
    Ok(組み立て規則::木(規則))
}

fn 名前(綴り: &str) -> Result<接合点名, String> {
    接合点名::生成する(綴り).map_err(|誤り| 誤り.to_string())
}

fn 識別子(綴り: &str) -> Result<部品ID, String> {
    部品ID::生成する(綴り).map_err(|誤り| 誤り.to_string())
}
