//! 地面へ部品で組んだ個体を散らす宣言と、その宣言をコンパイラが受け取る指定へ写す工程。
//!
//! 原型を散らす宣言と型を分けるのは、散らす先が1つの原型でなく部品の一覧と組み立て規則だからである。
//! 散らす場所の決め方(密度場と傾きと出現の判定)はまったく同じものを使い、写しを持たない。
//!
//! 規則そのものでなく種類を持つのは、`ソース種別`を`Copy`のまま保つためである。規則の値は増分の鍵の綴りへ
//! そのまま載るため、規則を変えた実行は材料が同じでもチャンクを焼き直す。
//! 参照: `_doc/設計/部品カタログと接合点.md`「段6: 散布の針葉樹を部品で組んだ木へ差し替える」

use blitz_asset_compiler::{密度場の散布, 部品で組む散布の指定};
use blitz_engine::アセットID;

use super::super::archetype_identity::原型の識別;
use super::assembly_rule_choice::部品の組み立て規則の種類;

/// 地面へ部品で組んだ個体を1種散らす宣言。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 部品で組む散布の宣言 {
    /// カタログへ載せる部品。規則が指す部品はすべてこの一覧に在る必要がある。
    pub(crate) 部品一覧: &'static [原型の識別],
    pub(crate) 規則の種類: 部品の組み立て規則の種類,
    pub(crate) 密度場の散布: 密度場の散布,
}

/// 宣言の並びを、コンパイラが受け取る指定の並びへ写す。
pub(crate) fn 部品で組む散布の指定一覧を作る(
    宣言一覧: &[部品で組む散布の宣言],
) -> Result<Vec<部品で組む散布の指定>, String> {
    宣言一覧.iter().map(指定を1件作る).collect()
}

fn 指定を1件作る(宣言: &部品で組む散布の宣言) -> Result<部品で組む散布の指定, String> {
    let 部品の安定id一覧 = 宣言
        .部品一覧
        .iter()
        .map(|識別| アセットID::生成する(識別.安定id()).map_err(|誤り| 誤り.to_string()))
        .collect::<Result<Vec<アセットID>, String>>()?;
    let (規則, 種の起点) = 宣言.規則の種類.規則と種の起点を組む()?;
    Ok(部品で組む散布の指定 {
        部品の安定id一覧,
        規則,
        種の起点,
        密度場の散布: 宣言.密度場の散布,
    })
}
