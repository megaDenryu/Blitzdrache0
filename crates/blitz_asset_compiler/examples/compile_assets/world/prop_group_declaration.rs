//! 原型と置き方の宣言1件の組み立てと、宣言からコンパイラが受け取る指定への写し。担当するのはこの2つだけであり、
//! どの世界がどの原型をどこへ置くかは宣言する側が持つ。
//!
//! 組み立てを関数にするのは、宣言の表の1行を1行に収めるためである。フィールド名の並びをここが持つことで、
//! 世界ごとの宣言の表が「どの原型を置くか」だけで読めるようになる。

use blitz_asset_compiler::{個数を決める並べ方, 原型と置き方の指定, 配置様式};
use blitz_engine::アセットID;

use super::super::source_kind::原型と置き方の宣言;

pub(super) const fn 小物(安定id: &'static str, ソース相対パス: &'static str, 配置様式: 配置様式) -> 原型と置き方の宣言 {
    原型と置き方の宣言 {
        原型の安定id: 安定id,
        ソース相対パス,
        配置様式,
    }
}

pub(super) const fn 輪(個体数: usize, 半径メートル: f32, ばらつきメートル: f32) -> 配置様式 {
    配置様式::個数を決めて並べる(個数を決める並べ方::輪に沿う {
        個体数,
        半径メートル,
        ばらつきメートル,
    })
}

pub(super) const fn 集まり(個体数: usize, 中心xメートル: f32, 中心zメートル: f32, 半径メートル: f32) -> 配置様式 {
    配置様式::個数を決めて並べる(個数を決める並べ方::集まり {
        個体数,
        中心xメートル,
        中心zメートル,
        半径メートル,
    })
}

pub(super) const fn 散らす(個体数: usize, 一辺メートル: f32) -> 配置様式 {
    配置様式::個数を決めて並べる(個数を決める並べ方::一様に散らす {
        個体数, 一辺メートル
    })
}

/// 宣言が持つ安定IDの綴りを検証済みのアセットIDへ写す。宣言側が`Copy`のまま綴りを持つのは、`ソース種別`を`Copy`に保つためである。
pub(crate) fn 原型と置き方の指定一覧を作る(
    群一覧: &[原型と置き方の宣言]
) -> Result<Vec<原型と置き方の指定>, String> {
    群一覧
        .iter()
        .map(|宣言| {
            Ok(原型と置き方の指定 {
                原型id: アセットID::生成する(宣言.原型の安定id).map_err(|誤り| 誤り.to_string())?,
                配置様式: 宣言.配置様式,
            })
        })
        .collect()
}
