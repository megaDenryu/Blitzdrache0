//! 小物群の宣言1件の組み立てと、宣言からコンパイラが受け取る指定への写し。担当するのはこの2つだけであり、
//! どの世界がどの小物を何体どこへ置くかは宣言する側が持つ。
//!
//! 組み立てを関数にするのは、宣言の表の1行を1行に収めるためである。フィールド名の並びをここが持つことで、
//! 世界ごとの宣言の表が「どの小物を置くか」だけで読めるようになる。

use blitz_asset_compiler::{小物群の指定, 配置様式};
use blitz_engine::アセットID;

use super::super::source_kind::小物群宣言;

pub(super) const fn 小物(
    安定id: &'static str, ソース相対パス: &'static str, 個体数: usize, 配置様式: 配置様式
) -> 小物群宣言 {
    小物群宣言 {
        原型の安定id: 安定id,
        ソース相対パス,
        個体数,
        配置様式,
    }
}

pub(super) const fn 輪(半径メートル: f32, ばらつきメートル: f32) -> 配置様式 {
    配置様式::輪に沿う {
        半径メートル,
        ばらつきメートル,
    }
}

pub(super) const fn 集まり(中心xメートル: f32, 中心zメートル: f32, 半径メートル: f32) -> 配置様式 {
    配置様式::集まり {
        中心xメートル,
        中心zメートル,
        半径メートル,
    }
}

pub(super) const fn 散らす(一辺メートル: f32) -> 配置様式 {
    配置様式::一様に散らす { 一辺メートル }
}

/// 宣言が持つ安定IDの綴りを検証済みのアセットIDへ写す。宣言側が`Copy`のまま綴りを持つのは、`ソース種別`を`Copy`に保つためである。
pub(crate) fn 群の指定一覧を作る(群一覧: &[小物群宣言]) -> Result<Vec<小物群の指定>, String> {
    群一覧
        .iter()
        .map(|宣言| {
            Ok(小物群の指定 {
                原型id: アセットID::生成する(宣言.原型の安定id).map_err(|誤り| 誤り.to_string())?,
                個体数: 宣言.個体数,
                配置様式: 宣言.配置様式,
            })
        })
        .collect()
}
