//! アセット定義1件の組み立て。必須か任意か、実行時形式まで焼くか焼かないか、どのルートから引くかの組み合わせを
//! 呼び出し側がフィールドで書くと、世界の一覧が「どのアセットを宣言するか」でなく「定義の作り方」で埋まる。
//! 4つの組み合わせに名前を与えてここが所有する。

use super::super::catalog::{アセット定義, ソース種別};
use super::super::source_location::ソースの基準;

pub(super) fn 必須定義(名前: &'static str, 相対パス: &'static str, 種別: ソース種別) -> アセット定義 {
    アセット定義 {
        名前,
        相対パス,
        基準: ソースの基準::本体のソースルート,
        必須: true,
        実行時へ焼く: true,
        種別,
    }
}

/// 他のアセットが素材として読むだけのソース。コンパイル時カタログへは載せ、実行時形式は焼かない。
/// 焼くと、どこからも読まれない生成物がカタログへ残り、実行時の解決対象が実体と食い違う。
pub(super) fn ソース専用定義(名前: &'static str, 相対パス: &'static str) -> アセット定義 {
    アセット定義 {
        名前,
        相対パス,
        基準: ソースの基準::本体のソースルート,
        必須: true,
        実行時へ焼く: false,
        種別: ソース種別::Gltfシーン,
    }
}

/// 標準サンプルは`fetch-assets`で取得するまで存在しないため、無ければ飛ばす。
pub(super) fn 任意定義(名前: &'static str, 相対パス: &'static str) -> アセット定義 {
    アセット定義 {
        名前,
        相対パス,
        基準: ソースの基準::本体のソースルート,
        必須: false,
        実行時へ焼く: true,
        種別: ソース種別::Gltfシーン,
    }
}

/// 本体リポジトリの外にあるアセットリポジトリのglTFシーン。ルートそのものが無い環境ではその旨を告げて飛ばし、
/// ルートがあるのに宣言したファイルが無いときは宣言の破れとして失敗させる。飛ばす側にするのは、
/// このアセットリポジトリがリモートを持たず複製できないため、ルートが無い環境が正当に成立するからである。
pub(super) fn 外部アセット定義(名前: &'static str, 相対パス: &'static str) -> アセット定義 {
    アセット定義 {
        名前,
        相対パス,
        基準: ソースの基準::外部ソースルート,
        必須: true,
        実行時へ焼く: true,
        種別: ソース種別::Gltfシーン,
    }
}
