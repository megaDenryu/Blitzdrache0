//! 骨格方式の3つの規則が共有する材料。部品と接合点の綴り・骨格の面へ壁を食い込ませる量・はめ口1つの指定を
//! 組む工程を持つ。
//!
//! 規則そのもの(`frame_rule`と`frame_chain_rule`)から分けるのは、綴りが3つへ写ると、Blender側が部品の名前を
//! 変えたときに1つだけ直し忘れる形の食い違いが起きるためである。
//!
//! **壁の位置も向きも書かない。** はめ口が面の位置と姿勢を宣言しており、壁がどの向きで立つかは接合が決める。
//!
//! 食い込ませる量0.02メートルは、部品の寸法から導出できない配置の決定である。零にすると骨格の柱と梁の外面(1.00)と
//! 壁の背面がちょうど同一平面になり、深度が競合する。**この破れは接触の検査に掛からず絵にだけ出る。**
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格と壁の対、扉の対」

use blitz_assembly::{
    はめ口の指定, はめ口へ入れるもの, 接合点名, 法線方向のずらし, 部品ID, 骨格へ張る床, 骨格へ継ぎ足すもの
};
use blitz_math::メートル;

const 食い込ませる量: f32 = 0.02;

/// 壁3種が共通で持つ、骨格のはめ口と噛み合う接合点の名前。
const 壁の外枠: &str = "壁の外枠";

pub(super) const 骨格の綴り: &str = "Mod_Frame_Bay_Single";
pub(super) const 平壁の綴り: &str = "Mod_Wall_HalfTimber_Solid";
pub(super) const 窓壁の綴り: &str = "Mod_Wall_HalfTimber_Window";
pub(super) const 扉枠付きの壁の綴り: &str = "Mod_Wall_HalfTimber_DoorFrame";
pub(super) const 切妻屋根の綴り: &str = "Mod_Frame_Roof_Gable";
pub(super) const 床板の綴り: &str = "Mod_Frame_Floor";

/// 候補が1つだけのはめ口。その面には必ずその壁が入る。
pub(super) fn 必ず入れるはめ口(はめ口の綴り: &str, 部品の綴り: &str) -> Result<はめ口の指定, String> {
    指定を組む(はめ口の綴り, vec![壁をはめる(部品の綴り)?])
}

/// 何も入れないか平壁か窓壁かを3分の1ずつで引くはめ口。候補の数がそのまま割合を決める。
pub(super) fn 選べるはめ口(はめ口の綴り: &str) -> Result<はめ口の指定, String> {
    let 候補一覧 = vec![はめ口へ入れるもの::入れない, 壁をはめる(平壁の綴り)?, 壁をはめる(窓壁の綴り)?];
    指定を組む(はめ口の綴り, 候補一覧)
}

/// 骨格の上面へ屋根を載せる候補。屋根が宣言する接合点は下面積層1件だけであり、その上へ継げるものは無い。
pub(super) fn 屋根を載せる候補() -> Result<骨格へ継ぎ足すもの, String> {
    Ok(骨格へ継ぎ足すもの::屋根を載せる {
        部品: 識別子(切妻屋根の綴り)?,
        下面: 名前("屋根の下面")?,
    })
}

/// 骨格の床のはめ口へ床板を1枚張る宣言。**種で引かないのは、床の抜けが意匠の振れでなく破れに見えるためである。**
/// 食い込ませる量を持たないのは、床のはめ口と床の外枠が面の向かい合う隣接であり、重なる面をそもそも持たないためである。
pub(super) fn 床を張る宣言() -> Result<骨格へ張る床, String> {
    Ok(骨格へ張る床::床を張る {
        部品: 識別子(床板の綴り)?,
        床のはめ口: 名前("床のはめ口")?,
        床の外枠: 名前("床の外枠")?,
    })
}

pub(super) fn 名前(綴り: &str) -> Result<接合点名, String> {
    接合点名::生成する(綴り).map_err(|誤り| 誤り.to_string())
}

pub(super) fn 識別子(綴り: &str) -> Result<部品ID, String> {
    部品ID::生成する(綴り).map_err(|誤り| 誤り.to_string())
}

fn 指定を組む(はめ口の綴り: &str, 候補一覧: Vec<はめ口へ入れるもの>) -> Result<はめ口の指定, String> {
    はめ口の指定::生成する(名前(はめ口の綴り)?, 候補一覧).map_err(|誤り| 誤り.to_string())
}

fn 壁をはめる(部品の綴り: &str) -> Result<はめ口へ入れるもの, String> {
    Ok(はめ口へ入れるもの::壁をはめる {
        部品: 識別子(部品の綴り)?,
        外枠: 名前(壁の外枠)?,
        法線方向のずらし: 法線方向のずらし::食い込ませる量から生成する(メートル::生成する(食い込ませる量))
            .map_err(|誤り| 誤り.to_string())?,
    })
}
