//! 骨格を連ねる4つの規則。上へ2段積む見本・横へ2ベイ継ぐ見本・屋根を載せた1ベイの家・屋根を載せた2段の家である。
//! 1ベイ1段の規則は`frame_rule`が、5つが共有する材料は`frame_bay_choice`が、階ごとの壁の割り当ては
//! `frame_wall_assignment`が持つ。
//!
//! **床を張るのは家2件だけである。** 2段積みと2ベイの見本は骨格そのものの継ぎ方を絵にするためのものであり、
//! Blender側の正解表もその2件へ床を含めていない。床を骨格に必ず付随させると、見本の絵と突き合わせが食い違う。
//!
//! 骨格をどこへどれだけ進めるかも屋根がどこへ載るかも床がどの高さに張られるかも1つも書かない。階高2.60メートルと
//! 屋根の高さは骨格の上面の宣言が、横へ進む2.00メートルは左右の継ぎ口の位置の差が、床の高さ0.16メートルは
//! 床のはめ口の宣言が導く。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格の上下積層とベイの継ぎ口(2026-08-19 追加)」

use blitz_assembly::{
    はめ口の指定, 一間四方の骨格の規則, 組み立て規則, 継ぎ足しの指定, 骨格へ張る床, 骨格へ継ぎ足すもの
};

use super::frame_bay_choice::{名前, 屋根を載せる候補, 床を張る宣言, 識別子, 骨格の綴り};
use super::frame_wall_assignment::{
    一階のはめ口一覧, 二階のはめ口一覧, 右のベイのはめ口一覧, 左のベイのはめ口一覧
};

/// 1階へ扉枠付きの壁と窓壁と平壁2枚、2階の正面へ窓壁を入れて、階で違う壁が入ることを絵に出す。床は張らない。
pub(super) fn 二段に積んだ骨格の規則を組む() -> Result<組み立て規則, String> {
    骨格を連ねた規則を組む(
        骨格へ張る床::張らない,
        一階のはめ口一覧()?,
        vec![上面へ骨格を積む段(骨格へ張る床::張らない)?],
    )
}

/// 1ベイへ床を1枚張り、上へ切妻屋根を載せた家。
pub(super) fn 屋根を載せた一間四方の家の規則を組む() -> Result<組み立て規則, String> {
    骨格を連ねた規則を組む(床を張る宣言()?, 一階のはめ口一覧()?, vec![上面へ屋根を載せる段()?])
}

/// 2段に積んだ骨格の階ごとに床を1枚ずつ張り、上へ切妻屋根を載せた家。屋根の高さは階高の2段ぶんの累和になる。
pub(super) fn 屋根を載せた二段の家の規則を組む() -> Result<組み立て規則, String> {
    骨格を連ねた規則を組む(
        床を張る宣言()?,
        一階のはめ口一覧()?,
        vec![上面へ骨格を積む段(床を張る宣言()?)?, 上面へ屋根を載せる段()?],
    )
}

/// 左のベイの右面と右のベイの左面が継ぎに使われるため、その2面には壁を入れない。床は張らない。
pub(super) fn 横に二ベイ継いだ骨格の規則を組む() -> Result<組み立て規則, String> {
    let 右のベイ = 継ぎ足しの指定::生成する(
        名前("右面の継ぎ口")?,
        vec![骨格へ継ぎ足すもの::骨格を継ぐ {
            自分の接合点: 名前("左面の継ぎ口")?,
            床: 骨格へ張る床::張らない,
            はめ口一覧: 右のベイのはめ口一覧()?,
        }],
    )
    .map_err(|誤り| 誤り.to_string())?;
    骨格を連ねた規則を組む(骨格へ張る床::張らない, 左のベイのはめ口一覧()?, vec![右のベイ])
}

fn 上面へ骨格を積む段(継いだ骨格の床: 骨格へ張る床) -> Result<継ぎ足しの指定, String> {
    上面の段を組む(骨格へ継ぎ足すもの::骨格を継ぐ {
        自分の接合点: 名前("骨格の下面")?,
        床: 継いだ骨格の床,
        はめ口一覧: 二階のはめ口一覧()?,
    })
}

fn 上面へ屋根を載せる段() -> Result<継ぎ足しの指定, String> {
    上面の段を組む(屋根を載せる候補()?)
}

fn 上面の段を組む(候補: 骨格へ継ぎ足すもの) -> Result<継ぎ足しの指定, String> {
    継ぎ足しの指定::生成する(名前("骨格の上面")?, vec![候補]).map_err(|誤り| 誤り.to_string())
}

fn 骨格を連ねた規則を組む(
    根の床: 骨格へ張る床,
    根のはめ口一覧: Vec<はめ口の指定>,
    連なり: Vec<継ぎ足しの指定>,
) -> Result<組み立て規則, String> {
    Ok(組み立て規則::一間四方の骨格(一間四方の骨格の規則::生成する(
        識別子(骨格の綴り)?,
        根の床,
        根のはめ口一覧,
        連なり,
    )))
}
