//! 骨格を連ねる2つの規則。上へ2段積む見本と、横へ2ベイ継ぐ見本である。
//! 1ベイ1段の規則は`frame_rule`が、3つが共有する材料は`frame_bay_choice`が持つ。
//!
//! **どの面にも候補を1つだけ置き、種で姿が変わらないようにしてある。** この2つの世界の目的は、正解表との
//! 突き合わせが通った組み立てそのものを絵にして、境目の意匠と深度の競合を人が見ることである。種で壁が変わると、
//! 絵に写ったものが突き合わせで確かめた組み立てと同じであることを言えなくなる。
//!
//! **継いだ面のはめ口を並べない。** 壁のはめ口とベイの継ぎ口は骨格の同じ物理面へ重ねて宣言されているため、
//! 両方を使うと壁と隣のベイが同じ面へ二重に入る。**この排他は規則の責務であり、接合の契約は課さない。**
//!
//! 骨格をどこへどれだけ進めるかは1つも書かない。階高2.60メートルは骨格の上面の宣言が、横へ進む2.00メートルは
//! 左右の継ぎ口の位置の差が導く。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格の上下積層とベイの継ぎ口(2026-08-19 追加)」

use blitz_assembly::{はめ口の指定, 一間四方の骨格の規則, 組み立て規則, 骨格の継ぎ足し};

use super::frame_bay_choice::{
    名前, 平壁の綴り, 必ず入れるはめ口, 扉枠付きの壁の綴り, 窓壁の綴り, 識別子, 骨格の綴り
};

/// 1階へ扉枠付きの壁と窓壁と平壁2枚、2階の正面へ窓壁を入れて、階で違う壁が入ることを絵に出す。
pub(super) fn 二段に積んだ骨格の規則を組む() -> Result<組み立て規則, String> {
    let 一階のはめ口一覧 = vec![
        必ず入れるはめ口("正面のはめ口", 扉枠付きの壁の綴り)?,
        必ず入れるはめ口("左面のはめ口", 窓壁の綴り)?,
        必ず入れるはめ口("背面のはめ口", 平壁の綴り)?,
        必ず入れるはめ口("右面のはめ口", 平壁の綴り)?,
    ];
    let 二階 = 骨格の継ぎ足し::生成する(名前("骨格の上面")?, 名前("骨格の下面")?, 二階のはめ口一覧()?);
    骨格を連ねた規則を組む(一階のはめ口一覧, 二階)
}

fn 二階のはめ口一覧() -> Result<Vec<はめ口の指定>, String> {
    Ok(vec![
        必ず入れるはめ口("正面のはめ口", 窓壁の綴り)?,
        必ず入れるはめ口("左面のはめ口", 窓壁の綴り)?,
        必ず入れるはめ口("背面のはめ口", 平壁の綴り)?,
        必ず入れるはめ口("右面のはめ口", 平壁の綴り)?,
    ])
}

/// 左のベイの右面と右のベイの左面が継ぎに使われるため、その2面には壁を入れない。
pub(super) fn 横に二ベイ継いだ骨格の規則を組む() -> Result<組み立て規則, String> {
    let 左のベイのはめ口一覧 = vec![
        必ず入れるはめ口("正面のはめ口", 扉枠付きの壁の綴り)?,
        必ず入れるはめ口("左面のはめ口", 窓壁の綴り)?,
        必ず入れるはめ口("背面のはめ口", 平壁の綴り)?,
    ];
    let 右のベイのはめ口一覧 = vec![
        必ず入れるはめ口("正面のはめ口", 窓壁の綴り)?,
        必ず入れるはめ口("右面のはめ口", 平壁の綴り)?,
        必ず入れるはめ口("背面のはめ口", 平壁の綴り)?,
    ];
    let 右のベイ = 骨格の継ぎ足し::生成する(名前("右面の継ぎ口")?, 名前("左面の継ぎ口")?, 右のベイのはめ口一覧);
    骨格を連ねた規則を組む(左のベイのはめ口一覧, 右のベイ)
}

fn 骨格を連ねた規則を組む(
    根のはめ口一覧: Vec<はめ口の指定>, 継ぎ足し: 骨格の継ぎ足し
) -> Result<組み立て規則, String> {
    Ok(組み立て規則::一間四方の骨格(一間四方の骨格の規則::生成する(
        識別子(骨格の綴り)?,
        根のはめ口一覧,
        vec![継ぎ足し],
    )))
}
