//! 骨格を連ねた見本の、骨格1つぶんの壁の割り当て。1階・2階・左のベイ・右のベイの4通りを持つ。
//!
//! **どの面にも候補を1つだけ置き、種で姿が変わらないようにしてある。** これらの世界の目的は、正解表との
//! 突き合わせが通った組み立てそのものを絵にして、境目の意匠と深度の競合を人が見ることである。種で壁が変わると、
//! 絵に写ったものが突き合わせで確かめた組み立てと同じであることを言えなくなる。
//!
//! 規則(`frame_chain_rule`)から分けるのは、この割り当てが複数の規則から呼ばれる材料だからである。呼び出し側は
//! 中身を知らずに「1階ぶんの壁」「右のベイぶんの壁」として受け取り、連なりの形だけを自分で決める。
//!
//! **継いだ面のはめ口を並べない。** 壁のはめ口とベイの継ぎ口は骨格の同じ物理面へ重ねて宣言されているため、
//! 両方を使うと壁と隣のベイが同じ面へ二重に入る。**この排他は規則の責務であり、接合の契約は課さない。**

use blitz_assembly::はめ口の指定;

use super::frame_bay_choice::{外面へ出窓を差し込むはめ口, 外面へ煙突を立てるはめ口, 平壁の綴り};
use super::frame_bay_choice::{必ず入れるはめ口, 扉枠付きの壁の綴り, 窓壁の綴り};

/// 正面へ扉枠付きの壁、左面へ窓壁、背面と右面へ平壁を入れる。1ベイ1段の見本と2段積みの1階が使う。
pub(super) fn 一階のはめ口一覧() -> Result<Vec<はめ口の指定>, String> {
    Ok(vec![
        必ず入れるはめ口("正面のはめ口", 扉枠付きの壁の綴り)?,
        必ず入れるはめ口("左面のはめ口", 窓壁の綴り)?,
        必ず入れるはめ口("背面のはめ口", 平壁の綴り)?,
        必ず入れるはめ口("右面のはめ口", 平壁の綴り)?,
    ])
}

/// 1階の割り当てのうち、背面の平壁だけが外面へ出窓を差し込む。**屋根つきの1ベイの家だけがこれを使う。**
/// 正解表が出窓を持つのはその1件だけであり、絵に写ったものが突き合わせで確かめた組み立てと同じであることを保つ。
pub(super) fn 背面へ出窓を差し込む一階のはめ口一覧() -> Result<Vec<はめ口の指定>, String> {
    Ok(vec![
        必ず入れるはめ口("正面のはめ口", 扉枠付きの壁の綴り)?,
        必ず入れるはめ口("左面のはめ口", 窓壁の綴り)?,
        外面へ出窓を差し込むはめ口("背面のはめ口", 平壁の綴り)?,
        必ず入れるはめ口("右面のはめ口", 平壁の綴り)?,
    ])
}

/// 1階の割り当てのうち、背面の平壁が外面へ出窓を差し込み、右面の平壁が外面へ煙突を立てる。
/// **煙突を付けた1ベイの家だけがこれを使う。** Blender側の正解表`Frame_Bay_House_Chimney`が持つ組み立てと
/// 同じ割り当てであり、絵に写ったものが突き合わせで確かめた組み立てと同じであることを保つ。
pub(super) fn 背面へ出窓と右面へ煙突を付ける一階のはめ口一覧() -> Result<Vec<はめ口の指定>, String> {
    Ok(vec![
        必ず入れるはめ口("正面のはめ口", 扉枠付きの壁の綴り)?,
        必ず入れるはめ口("左面のはめ口", 窓壁の綴り)?,
        外面へ出窓を差し込むはめ口("背面のはめ口", 平壁の綴り)?,
        外面へ煙突を立てるはめ口("右面のはめ口", 平壁の綴り)?,
    ])
}

/// 正面を窓壁にして、階で違う壁が入ることを絵に出す。
pub(super) fn 二階のはめ口一覧() -> Result<Vec<はめ口の指定>, String> {
    Ok(vec![
        必ず入れるはめ口("正面のはめ口", 窓壁の綴り)?,
        必ず入れるはめ口("左面のはめ口", 窓壁の綴り)?,
        必ず入れるはめ口("背面のはめ口", 平壁の綴り)?,
        必ず入れるはめ口("右面のはめ口", 平壁の綴り)?,
    ])
}

/// 右面を隣のベイへの継ぎに使うため、その面には壁を入れない。
pub(super) fn 左のベイのはめ口一覧() -> Result<Vec<はめ口の指定>, String> {
    Ok(vec![
        必ず入れるはめ口("正面のはめ口", 扉枠付きの壁の綴り)?,
        必ず入れるはめ口("左面のはめ口", 窓壁の綴り)?,
        必ず入れるはめ口("背面のはめ口", 平壁の綴り)?,
    ])
}

/// 左面が継ぎに使われているため、その面には壁を入れない。
pub(super) fn 右のベイのはめ口一覧() -> Result<Vec<はめ口の指定>, String> {
    Ok(vec![
        必ず入れるはめ口("正面のはめ口", 窓壁の綴り)?,
        必ず入れるはめ口("右面のはめ口", 平壁の綴り)?,
        必ず入れるはめ口("背面のはめ口", 平壁の綴り)?,
    ])
}
