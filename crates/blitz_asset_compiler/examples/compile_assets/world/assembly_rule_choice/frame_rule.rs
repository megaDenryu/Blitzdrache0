//! 一間四方の骨格を1ベイ1段で建てる規則。骨格1件の4つのはめ口へ、壁3種のどれかを入れるか何も入れないかを種から選ぶ。
//! 骨格を連ねる2つの規則は`frame_chain_rule`が、3つが共有する材料は`frame_bay_choice`が持つ。
//!
//! **壁3種それぞれに必ず入れる面を割り当てる。** 正面へ扉枠付きの壁、背面へ平壁、左面へ窓壁を必ず入れ、
//! 右面だけを候補で振り分ける。全面を選ばせると、たまたま扉枠付きの壁が1棟も選ばれない種があり得て、
//! 部品の種類数が種で変わる。それは発行数が件数に依らないことの実証の前提を壊す。
//! 家の規則が3階の正面壁と屋根の破風正面壁を必ず付けているのと同じ理由である。
//!
//! 展開の種の起点を骨格方式の3つの規則で共有するのは、どれも同じ部品の同じはめ口から壁を引くためである。
//! 見本の2つは全面を必ず入れる面にしてあるため、種は壁の選択に効かない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格と壁の対、扉の対」

use blitz_assembly::{一間四方の骨格の規則, 生成の種, 組み立て規則};

use super::frame_bay_choice::{
    平壁の綴り, 必ず入れるはめ口, 扉枠付きの壁の綴り, 窓壁の綴り, 識別子, 選べるはめ口, 骨格の綴り
};

/// 一間四方の骨格の並びの展開の種の起点。1件ごとにこの値から番号で分けた種を作る。値を固定するのは、
/// 同じ宣言から同じ配置を得るためである。
const 種の値: u64 = 0x4672_616D_6552_6F77;

pub(super) fn 一間四方の骨格の並びの展開の種() -> 生成の種 {
    生成の種::値から生成する(種の値)
}

pub(super) fn 一間四方の骨格の規則を組む() -> Result<組み立て規則, String> {
    let はめ口一覧 = vec![
        必ず入れるはめ口("正面のはめ口", 扉枠付きの壁の綴り)?,
        必ず入れるはめ口("背面のはめ口", 平壁の綴り)?,
        必ず入れるはめ口("左面のはめ口", 窓壁の綴り)?,
        選べるはめ口("右面のはめ口")?,
    ];
    Ok(組み立て規則::一間四方の骨格(一間四方の骨格の規則::生成する(
        識別子(骨格の綴り)?,
        はめ口一覧,
        Vec::new(),
    )))
}
