//! 一間四方の骨格の組み立て規則。骨格1件の4つのはめ口へ、壁3種のどれかを入れるか何も入れないかを種から選ぶ。
//!
//! **壁3種それぞれに必ず入れる面を割り当てる。** 正面へ扉枠付きの壁、背面へ平壁、左面へ窓壁を必ず入れ、
//! 右面だけを候補で振り分ける。全面を選ばせると、たまたま扉枠付きの壁が1棟も選ばれない種があり得て、
//! 部品の種類数が種で変わる。それは発行数が件数に依らないことの実証の前提を壊す。
//! 家の規則が3階の正面壁と屋根の破風正面壁を必ず付けているのと同じ理由である。
//!
//! **壁の位置も向きも書かない。** はめ口が面の位置と姿勢を宣言しており、壁がどの向きで立つかは接合が決める。
//! 4つのはめ口は向きだけが違い上方向がどれも天頂であるため、壁は天頂軸まわりに0度・90度・180度・270度だけ回る。
//!
//! 食い込ませる量0.02メートルは、部品の寸法から導出できない配置の決定である。零にすると骨格の柱と梁の外面(1.00)と
//! 壁の背面がちょうど同一平面になり、深度が競合する。**この破れは接触の検査に掛からず絵にだけ出る。**
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格と壁の対、扉の対」

use blitz_assembly::{
    はめ口の指定, はめ口へ入れるもの, 一間四方の骨格の規則, 接合点名, 法線方向のずらし, 生成の種, 組み立て規則, 部品ID
};
use blitz_math::メートル;

/// 一間四方の骨格の並びの展開の種の起点。1件ごとにこの値から番号で分けた種を作る。値を固定するのは、
/// 同じ宣言から同じ配置を得るためである。
const 種の値: u64 = 0x4672_616D_6552_6F77;

/// 骨格の面へ壁を食い込ませる量。2026-08-18の裁定で決めた仮値であり、絵で最終確定する。
const 食い込ませる量: f32 = 0.02;

/// 壁3種が共通で持つ、骨格のはめ口と噛み合う接合点の名前。
const 壁の外枠: &str = "壁の外枠";

pub(super) fn 一間四方の骨格の並びの展開の種() -> 生成の種 {
    生成の種::値から生成する(種の値)
}

pub(super) fn 一間四方の骨格の規則を組む() -> Result<組み立て規則, String> {
    let はめ口一覧 = vec![
        必ず入れるはめ口("正面のはめ口", "Mod_Wall_HalfTimber_DoorFrame")?,
        必ず入れるはめ口("背面のはめ口", "Mod_Wall_HalfTimber_Solid")?,
        必ず入れるはめ口("左面のはめ口", "Mod_Wall_HalfTimber_Window")?,
        選べるはめ口("右面のはめ口")?,
    ];
    Ok(組み立て規則::一間四方の骨格(一間四方の骨格の規則::生成する(
        識別子("Mod_Frame_Bay_Single")?,
        はめ口一覧,
    )))
}

/// 候補が1つだけのはめ口。その面には必ずその壁が入る。
fn 必ず入れるはめ口(はめ口の綴り: &str, 部品の綴り: &str) -> Result<はめ口の指定, String> {
    指定を組む(はめ口の綴り, vec![壁をはめる(部品の綴り)?])
}

/// 何も入れないか平壁か窓壁かを3分の1ずつで引くはめ口。候補の数がそのまま割合を決める。
fn 選べるはめ口(はめ口の綴り: &str) -> Result<はめ口の指定, String> {
    let 候補一覧 = vec![
        はめ口へ入れるもの::入れない,
        壁をはめる("Mod_Wall_HalfTimber_Solid")?,
        壁をはめる("Mod_Wall_HalfTimber_Window")?,
    ];
    指定を組む(はめ口の綴り, 候補一覧)
}

fn 指定を組む(はめ口の綴り: &str, 候補一覧: Vec<はめ口へ入れるもの>) -> Result<はめ口の指定, String> {
    はめ口の指定::生成する(名前(はめ口の綴り)?, 候補一覧).map_err(|誤り| 誤り.to_string())
}

fn 壁をはめる(部品の綴り: &str) -> Result<はめ口へ入れるもの, String> {
    Ok(はめ口へ入れるもの::壁をはめる {
        部品: 識別子(部品の綴り)?,
        外枠: 名前(壁の外枠)?,
        法線方向のずらし: 法線方向のずらし::食い込ませる量から生成する(メートル::生成する(食い込ませる量))
            .map_err(|誤り| 誤り.to_string())?,
    })
}

fn 名前(綴り: &str) -> Result<接合点名, String> {
    接合点名::生成する(綴り).map_err(|誤り| 誤り.to_string())
}

fn 識別子(綴り: &str) -> Result<部品ID, String> {
    部品ID::生成する(綴り).map_err(|誤り| 誤り.to_string())
}
