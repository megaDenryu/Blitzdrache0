//! 場所巡りの世界が焼くものの宣言。担当するのは、起動時に読むキツネのシーンと目印の原型と、目的地の大域の水平位置を
//! 1箇所へ集めることだけである。宣言をコンパイラが受け取る目印の据え付けへ写す手順もここが持つ。
//!
//! 注意: 目的地の大域の水平位置は、ゲームロジック層の道順(`crates/blitz_game/src/fox_tour_route.rs`)と同じ数でなければならない。
//! 食い違うと、目印の柱が立っていない場所で到達が成立するか、柱の足元で到達が成立しないかのどちらかになる。
//! 2つが別のクレートに分かれているのは、あちらがblitz_mathだけに依存するゲームロジック層であり、
//! こちらがアセットコンパイラの宣言だからである。整数のメートルで書くのは、2つの表を目で並べて突き合わせるためである。

use blitz_asset_compiler::目印の据え付け;
use blitz_engine::{アセットID, チャンク座標};

use super::super::catalog::アセット定義;
use super::super::source_kind::{ソース種別, 目的地の大域の水平位置};
use super::definition_kind::{ソース専用定義, 必須定義};

/// 起動時に読むキツネのシーンの安定ID。名前が`terrain`で始まることが、この世界の空方針・間接照明方針・露出方式を
/// 地形の本番世界と同じものにする。参照: `crates/blitz_app/src/app/time_of_day/scene_policy.rs`
pub(super) const キツネのシーン: (&str, &str) = ("terrain_fox_tour", "samples/Fox/Fox.glb");

/// キツネの標準サンプルを実寸へ合わせる倍率。ソースは体長がおよそ120で書かれているため、100分の1で体長1.2メートルになる。
const キツネの寸法の倍率: f32 = 0.01;

/// 目的地に立てる目印の柱の原型を指す安定ID。実行時形式は焼かず、目印を据えるチャンクが素材として読むだけである。
const 目印の柱: (&str, &str) = ("fox_tour_destination_marker", "fox_tour_world/destination_marker.gltf");

/// チャンク1つの一辺。生成側(`crates/blitz_asset_compiler/examples/generate_source_assets/fox_tour_world.rs`)と同じ値である。
const チャンクの一辺メートル: i32 = 100;

/// 巡る3つの目的地。1つ目は出発地点の真北にあり、2つ目と3つ目は向きを変えないと着かない位置に置く。
const 巡る目的地の一覧: &[目的地の大域の水平位置] = &[
    目的地の大域の水平位置 { 東メートル: 0, 南メートル: -15 },
    目的地の大域の水平位置 { 東メートル: -40, 南メートル: -45 },
    目的地の大域の水平位置 { 東メートル: 45, 南メートル: -70 },
];

pub(super) fn チャンクのソース種別() -> ソース種別 {
    ソース種別::目印つき高さ格子 {
        目印の原型の安定id: 目印の柱.0,
        目的地一覧: 巡る目的地の一覧,
    }
}

/// この世界がチャンク以外に焼くもの。キツネだけが実行時形式まで焼かれ、目印の原型はチャンクが素材として読むだけである。
pub(super) fn 一覧() -> Vec<アセット定義> {
    vec![
        必須定義(
            キツネのシーン.0,
            キツネのシーン.1,
            ソース種別::寸法を合わせるGltfシーン {
                一様倍率: キツネの寸法の倍率,
            },
        ),
        ソース専用定義(目印の柱.0, 目印の柱.1),
    ]
}

/// そのチャンクへ据える目印の一覧を作る。目的地の大域の水平位置をチャンク座標と局所の位置へ分け、
/// 所有チャンクに載るものだけを残す。1つも載らないチャンクは目印を持たない地面だけのチャンクとして焼かれる。
pub(crate) fn 目印の据え付け一覧を作る(
    目印の原型の安定id: &str,
    目的地一覧: &[目的地の大域の水平位置],
    所有チャンク: チャンク座標,
) -> Result<Vec<目印の据え付け>, String> {
    let mut 一覧 = Vec::new();
    for 目的地 in 目的地一覧 {
        let (東のチャンク成分, 局所の東) = 軸を分ける(目的地.東メートル)?;
        let (南のチャンク成分, 局所の南) = 軸を分ける(目的地.南メートル)?;
        if 東のチャンク成分 != 所有チャンク.x() || 南のチャンク成分 != 所有チャンク.z() {
            continue;
        }
        一覧.push(目印の据え付け {
            原型id: アセットID::生成する(目印の原型の安定id).map_err(|誤り| 誤り.to_string())?,
            チャンク原点からの東メートル: 局所の東,
            チャンク原点からの南メートル: 局所の南,
        });
    }
    Ok(一覧)
}

/// 1つの軸について、大域のメートルをチャンク座標の成分とチャンク原点からの局所メートルへ分ける。
/// 負の大域位置もゼロ方向へ丸めず床を取るため、チャンク座標の求め方はストリーミングの格子と同じである。
fn 軸を分ける(大域メートル: i32) -> Result<(i32, f32), String> {
    let 局所 = 大域メートル.rem_euclid(チャンクの一辺メートル);
    let 局所 = i16::try_from(局所).map_err(|_| format!("目的地の局所位置{局所}メートルが扱える範囲にない"))?;
    Ok((大域メートル.div_euclid(チャンクの一辺メートル), f32::from(局所)))
}
