//! 世界ごとのソースディレクトリ名の台帳と、対象世界からその名前を選ぶ引き当て。目録ソースのファイル名は
//! ライブラリの置き場の型が持つため、ここが持つのはディレクトリ名だけである。
//! 台帳を親から分けるのは、世界が増えるたびにこの一覧だけが伸び、宣言の引き当てと押し合うためである。
//! プロセス境界の綴りの台帳を`argument_name`が持つのと同じ分け方である。

use blitz_asset_compiler::場所巡りの世界のディレクトリ名;

use super::対象世界;

const 板の世界のディレクトリ名: &str = "chunk_world";
const 地形の世界のディレクトリ名: &str = "terrain_world";
const 植生の世界のディレクトリ名: &str = "vegetation_world";
const 見本の集落の世界のディレクトリ名: &str = "village_world";
const 目視見本の世界のディレクトリ名: &str = "terrain_visual_world";
const ブロック圧縮の対照世界のディレクトリ名: &str = "texture_compression_world";
const 夜の多光源の世界のディレクトリ名: &str = "night_lights_world";
const 屋内の多光源の世界のディレクトリ名: &str = "stone_hut_world";

/// 頂点診断の世界が地形の目録を読むのは、代表世界と同じ25チャンクの同じ地面を対象にするためである。
/// 場所巡りの世界の名前だけがライブラリ側にあるのは、乱数の種からソースを書き出す側と同じ1つを読むためである。
pub(super) fn 世界のソースディレクトリ名を選ぶ(世界: 対象世界) -> &'static str {
    match 世界 {
        対象世界::板の世界 => 板の世界のディレクトリ名,
        対象世界::地形の世界 | 対象世界::頂点診断の世界(_) => 地形の世界のディレクトリ名,
        対象世界::植生の世界 => 植生の世界のディレクトリ名,
        対象世界::見本の集落の世界 => 見本の集落の世界のディレクトリ名,
        対象世界::目視見本の世界 => 目視見本の世界のディレクトリ名,
        対象世界::ブロック圧縮の対照世界 => ブロック圧縮の対照世界のディレクトリ名,
        対象世界::夜の多光源の世界 => 夜の多光源の世界のディレクトリ名,
        対象世界::屋内の多光源の世界 => 屋内の多光源の世界のディレクトリ名,
        対象世界::場所巡りの世界 => 場所巡りの世界のディレクトリ名,
    }
}
