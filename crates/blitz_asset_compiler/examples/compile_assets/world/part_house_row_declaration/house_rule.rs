//! 酒場宿屋の組み立て規則。土台の上へ2つの階と屋根を積み、土台の左側面壁へ煙突を立て、
//! 残りの壁面ごとに出窓を付けるかどうかを種から選ぶ。
//!
//! **土台の左側面壁と3階の正面壁と屋根の破風正面壁は、付けない枝を持たせず必ず付ける。** 軒数を変えても
//! 部品の種類が変わらないことが段4の実証の前提であり、付ける付けないを全壁面で選ばせると、たまたま全軒で
//! その部品が選ばれない種があり得る。残りの3面は付けない側を厚くしてあり、同じ形の家が並ばない。
//!
//! 煙突だけは、必ず立てたまま壁に沿う位置を2つの候補で振り分ける。付ける付けないでなく位置で振り分けると、
//! 部品の種類数を動かさずに軒ごとの見た目を変えられる。煙突の差込面は0.7×3.0であり、高さが土台の壁面の3.0と
//! ちょうど同じであるため、収まる先は土台の側面壁だけである(2階は2.6、3階は2.4しかなく包含の検査で落ちる)。
//!
//! 面上の位置は部品の寸法から導出できない意匠の決定である。破風へ乗せるドーマーの横1.5メートルは、
//! Blender側の建築コードが`x_offset=1.5`と書いていた数値そのものである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合には2つの様式があり、検査すべきことが違う」

use blitz_assembly::{壁面の指定, 壁面の飾り, 家の規則, 接合点名, 生成の種, 積む階, 組み立て規則, 部品ID};
use blitz_math::メートル;

/// 家並みの展開の種の起点。軒ごとにこの値から番号で分けた種を作る。
/// 値を固定するのは、同じ宣言から同じ配置を得るためである。
const 種の値: u64 = 0x486F_7573_6552_6F77;

pub(super) fn 家並みの種() -> 生成の種 {
    生成の種::値から生成する(種の値)
}

pub(super) fn 酒場宿屋の規則() -> Result<組み立て規則, String> {
    let 煙突の候補 = vec![煙突を立てる(-1.2)?, 煙突を立てる(1.2)?];
    let 土台の壁面一覧 = vec![必ず付ける壁面("左側面壁", 煙突の候補)?, 選べる出窓("右側面壁")?];
    let 積む階一覧 = vec![
        階("Mod_Tavern_F2_Jetty", vec![選べる出窓("正面壁")?, 選べる出窓("背面壁")?])?,
        階("Mod_Tavern_F3_Jetty", vec![必ず付ける壁面("正面壁", vec![出窓を付ける()?])?])?,
        階("Mod_Tavern_Roof_Gable", vec![必ず付ける壁面("破風正面壁", vec![ドーマーを乗せる()?])?])?,
    ];
    Ok(組み立て規則::家(家の規則::生成する(
        識別子("Mod_Tavern_F1_Base")?,
        土台の壁面一覧,
        積む階一覧,
    )))
}

/// 直前の階の上面へ下面で積む階1件。実データの積層の接合点はどの階でも上面と下面の名前である。
fn 階(部品の綴り: &str, 壁面一覧: Vec<壁面の指定>) -> Result<積む階, String> {
    Ok(積む階 {
        部品: 識別子(部品の綴り)?,
        親の上面: 名前("上面")?,
        自分の下面: 名前("下面")?,
        壁面一覧,
    })
}

/// 付けない枝を持たない壁面。候補がどれも付ける枝であるため、その壁面には必ず何かが付く。
/// 候補が2つ以上あるときは、付くものは同じで置き方だけが軒ごとに変わる。
fn 必ず付ける壁面(壁面の綴り: &str, 候補一覧: Vec<壁面の飾り>) -> Result<壁面の指定, String> {
    壁面の指定::生成する(名前(壁面の綴り)?, 候補一覧).map_err(|誤り| 誤り.to_string())
}

/// 付けない枝を2つ並べ、付ける枝を1つ置いた壁面。3回に1回だけ出窓が付く。
/// 候補の数がそのまま割合を決めるため、割合を別の数で持たない。
fn 選べる出窓(壁面の綴り: &str) -> Result<壁面の指定, String> {
    let 候補一覧 = vec![壁面の飾り::付けない, 壁面の飾り::付けない, 出窓を付ける()?];
    壁面の指定::生成する(名前(壁面の綴り)?, 候補一覧).map_err(|誤り| 誤り.to_string())
}

fn 煙突を立てる(横のずらし: f32) -> Result<壁面の飾り, String> {
    飾りを組む("Mod_Tavern_Chimney", "壁面密着面", 横のずらし)
}

fn 出窓を付ける() -> Result<壁面の飾り, String> {
    飾りを組む("Mod_Tavern_Oriel_F2", "壁面差込口", 0.0)
}

fn ドーマーを乗せる() -> Result<壁面の飾り, String> {
    飾りを組む("Mod_Tavern_Dormer_Roof", "屋根面差込口", 1.5)
}

fn 飾りを組む(部品の綴り: &str, 接合点の綴り: &str, 横のずらし: f32) -> Result<壁面の飾り, String> {
    Ok(壁面の飾り::付ける {
        部品: 識別子(部品の綴り)?,
        接合点: 名前(接合点の綴り)?,
        横のずらし: メートル::生成する(横のずらし),
    })
}

fn 名前(綴り: &str) -> Result<接合点名, String> {
    接合点名::生成する(綴り).map_err(|誤り| 誤り.to_string())
}

fn 識別子(綴り: &str) -> Result<部品ID, String> {
    部品ID::生成する(綴り).map_err(|誤り| 誤り.to_string())
}
