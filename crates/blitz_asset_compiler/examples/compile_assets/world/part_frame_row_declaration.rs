//! 部品で組んだ一間四方の骨格の並びの世界が焼くものの宣言。担当するのは、カタログへ載せる部品4件と、
//! 世界ごとの件数と規則の引き当てである。宣言の型と、宣言を指定へ写す手順は`part_row_declaration`が持ち、
//! 組み立て規則そのものは`assembly_rule_choice`の`frame_rule`と`frame_chain_rule`が持つ。
//!
//! 1ベイ1段の世界が10棟と100棟の2つを持つのは、家の並びと同じ理由である。1つの規模だけでは、発行数が
//! たまたまその件数と一致しているのか件数に依らないのかを見分けられない。
//!
//! **骨格を連ねた2つの世界は件数の対を持たない。** 目的が発行数の実証でなく、境目の意匠と深度の競合を人が見る
//! ことだからである。件数を4にするのは、敷地が1件ごとに天頂軸まわりの4分の1回転を選ぶため、4件あれば
//! 継ぎ目と積み目を違う方位から同時に写せるからである。
//!
//! **家の並びと世界を分けるのは、組み立ての形が違うものを同じ計器で別々に見るためである。** 家は一体の階を積み、
//! 骨格は枠へ壁をはめる。同じ世界へ混ぜると、発行数が件数に依らないことが破れたときに、どちらの組み立てが
//! 壊したのかを絵と数から切り分けられない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格と壁の対、扉の対」

use super::super::catalog::{アセット定義, ソース種別};
use super::assembly_rule_choice::部品の組み立て規則の種類;
use super::part_row_declaration::{部品で組んだ並びの宣言, 部品のアセット定義一覧を作る};

/// 骨格方式の世界の種類。6つとも同じ地面を使い、違うのは件数と規則と、屋根を読むかどうかだけである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 一間四方の骨格の並びの種類 {
    十棟,
    百棟,
    二段に積んだ骨格の見本,
    横に二ベイ継いだ骨格の見本,
    屋根を載せた一間四方の家の見本,
    屋根を載せた二段の家の見本,
}

/// 骨格を連ねた見本を建てる件数。
const 見本の件数: usize = 4;

impl 一間四方の骨格の並びの種類 {
    fn 件数(self) -> usize {
        match self {
            Self::十棟 => 10,
            Self::百棟 => 100,
            Self::二段に積んだ骨格の見本
            | Self::横に二ベイ継いだ骨格の見本
            | Self::屋根を載せた一間四方の家の見本
            | Self::屋根を載せた二段の家の見本 => 見本の件数,
        }
    }

    fn 規則の種類(self) -> 部品の組み立て規則の種類 {
        match self {
            Self::十棟 | Self::百棟 => 部品の組み立て規則の種類::一間四方の骨格,
            Self::二段に積んだ骨格の見本 => 部品の組み立て規則の種類::二段に積んだ骨格,
            Self::横に二ベイ継いだ骨格の見本 => 部品の組み立て規則の種類::横に二ベイ継いだ骨格,
            Self::屋根を載せた一間四方の家の見本 => 部品の組み立て規則の種類::屋根を載せた一間四方の家,
            Self::屋根を載せた二段の家の見本 => 部品の組み立て規則の種類::屋根を載せた二段の家,
        }
    }
}

/// この世界がチャンク以外に焼くもの。**規則の種類が部品の一覧を答えるため、屋根を読む世界だけが5件になる。**
/// 一覧を種類と別に書くと、屋根を載せる規則の世界が屋根を読まない宣言が型を通り、
/// 「カタログに無い部品」という遠い場所の失敗になる。
pub(super) fn 一覧(種類: 一間四方の骨格の並びの種類) -> Vec<アセット定義> {
    部品のアセット定義一覧を作る(種類.規則の種類().部品一覧())
}

pub(super) fn チャンクのソース種別(種類: 一間四方の骨格の並びの種類) -> ソース種別 {
    ソース種別::部品で組んだ並び(部品で組んだ並びの宣言::生成する(種類.件数(), 種類.規則の種類()))
}
