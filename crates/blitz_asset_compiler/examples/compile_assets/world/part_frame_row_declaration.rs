//! 部品で組んだ一間四方の骨格の並びの世界が焼くものの宣言。担当するのは、カタログへ載せる部品4件と、何棟建てるかである。
//! 宣言の型と、宣言を指定へ写す手順は`part_row_declaration`が持ち、組み立て規則そのものは同じ場所の`frame_rule`が持つ。
//!
//! 10棟と100棟の2つの規模を持つのは、家の並びと同じ理由である。1つの規模だけでは、発行数がたまたまその件数と
//! 一致しているのか件数に依らないのかを見分けられない。
//!
//! **家の並びと世界を分けるのは、組み立ての形が違うものを同じ計器で別々に見るためである。** 家は一体の階を積み、
//! 骨格は枠へ壁をはめる。同じ世界へ混ぜると、発行数が件数に依らないことが破れたときに、どちらの組み立てが
//! 壊したのかを絵と数から切り分けられない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格と壁の対、扉の対」

use super::super::catalog::{アセット定義, ソース種別};
use super::assembly_rule_choice::部品の組み立て規則の種類;
use super::part_row_declaration::{部品で組んだ並びの宣言, 部品のアセット定義一覧を作る};

/// 一間四方の骨格の並びの規模。同じ地面と同じ規則で件数だけが違う2つの世界を、この枝が分ける。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 一間四方の骨格の並びの規模 {
    十棟,
    百棟,
}

impl 一間四方の骨格の並びの規模 {
    fn 件数(self) -> usize {
        match self {
            Self::十棟 => 10,
            Self::百棟 => 100,
        }
    }
}

/// この世界がチャンク以外に焼くもの。
pub(super) fn 一覧() -> Vec<アセット定義> {
    部品のアセット定義一覧を作る(部品の組み立て規則の種類::一間四方の骨格.部品一覧())
}

pub(super) fn チャンクのソース種別(規模: 一間四方の骨格の並びの規模) -> ソース種別 {
    ソース種別::部品で組んだ並び(部品で組んだ並びの宣言::生成する(
        規模.件数(),
        部品の組み立て規則の種類::一間四方の骨格,
    ))
}
