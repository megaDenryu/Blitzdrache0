//! 宣言したソースがどこに置かれているかの解決。担当するのは、アセット宣言が持つ基準と相対パスからソースの実パスを作ることと、
//! 本体リポジトリの外にあるソースの置き場を1箇所で決めることである。宣言の1行1行は起点を持たないため、置き場を移しても宣言は書き換えない。
//! 参照: `_doc/設計/Blenderアセット運用.md`「本体からの参照の仕組み」

use std::path::{Path, PathBuf};

/// 外部ソースルートの場所を上書きする環境変数。実行時アセットルートを指す`--asset-root`とは別物であり、こちらはソース側の置き場である。
const 環境変数名: &str = "BLITZDRACHE0_ASSET_SOURCE_ROOT";

/// 環境変数が無いときに探す場所。本体リポジトリと同じ親ディレクトリに並ぶアセットリポジトリの名前である。
const 隣接ディレクトリ名: &str = "Blitzdrache0Assets";

/// 宣言したソースをどのルートからの相対で参照するか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum ソースの基準 {
    /// 本体リポジトリのソースルート(`assets/`)からの相対。生成器が焼く検証用ソースはすべてこちらである。
    本体のソースルート,
    /// 本体リポジトリの外にあるアセットリポジトリからの相対。Blenderが生成したglbはこちらである。
    外部ソースルート,
}

/// 本体リポジトリの外にあるアセットリポジトリの置き場。このリポジトリはリモートを持たないため複製できず、存在しない環境が正当に成立する。
/// そのため不在を解決時の失敗にせず値として持ち、外部のソースを実際に引いた地点で初めて診断つきの失敗を返す。
pub(super) enum 外部ソースルート {
    利用可能(PathBuf),
    不在 { 診断: String },
}

impl 外部ソースルート {
    /// 環境変数があればその場所、無ければ本体リポジトリの隣接ディレクトリを見る。どちらの経路でも、見た場所を診断へ残す。
    pub(super) fn 解決する() -> Self {
        let 場所 = match std::env::var(環境変数名) {
            Ok(値) => PathBuf::from(値),
            Err(std::env::VarError::NotUnicode(値)) => {
                return Self::不在 {
                    診断: format!("環境変数{環境変数名}の値をパスとして読めない: {値:?}"),
                };
            }
            Err(std::env::VarError::NotPresent) => match 隣接する既定の場所() {
                Some(場所) => 場所,
                None => {
                    return Self::不在 {
                        診断: format!(
                            "本体リポジトリの隣接ディレクトリを求められない(クレートの位置: {})",
                            env!("CARGO_MANIFEST_DIR")
                        ),
                    };
                }
            },
        };
        if 場所.is_dir() {
            return Self::利用可能(場所);
        }
        Self::不在 {
            診断: format!(
                "{}がディレクトリとして存在しない(環境変数{環境変数名}で場所を上書きできる)",
                場所.display()
            ),
        }
    }
}

/// 本体リポジトリの隣に並ぶ既定の置き場。実行時の作業ディレクトリに依存させないため、コンパイル時のクレートの位置から辿る。
/// クレートは`<本体リポジトリ>/crates/blitz_asset_compiler`にあるため、3つ上が本体リポジトリの親になる。
fn 隣接する既定の場所() -> Option<PathBuf> {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(3)
        .map(|親ディレクトリ| 親ディレクトリ.join(隣接ディレクトリ名))
}

/// 宣言1件のソースの実パス。外部ソースルートが不在なら、どこを見て何が無かったかを添えて失敗させる。
pub(super) fn ソースパスを参照する(
    基準: ソースの基準,
    相対パス: &str,
    本体のソースルート: &Path,
    外部: &外部ソースルート,
) -> Result<PathBuf, String> {
    match 基準 {
        ソースの基準::本体のソースルート => Ok(本体のソースルート.join(相対パス)),
        ソースの基準::外部ソースルート => match 外部 {
            外部ソースルート::利用可能(ルート) => Ok(ルート.join(相対パス)),
            外部ソースルート::不在 { 診断 } => Err(format!("外部ソースルートを参照できないため{相対パス}を解決できない: {診断}")),
        },
    }
}
