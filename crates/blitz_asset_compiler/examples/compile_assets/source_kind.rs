//! コンパイル対象のソースが何の形式で書かれているかと、形式ごとに要る付随の宣言。
//! 読み方が形式ごとに違うため判別共用体で持ち、形式を1つ足すときに触る場所をここへ閉じる。
//! 宣言をカタログとコンパイル対象一覧へ写すのは`catalog`が、どの世界が何を宣言するかは`world`が持つ。

use blitz_asset_compiler::配置様式;

/// 地形チャンクへ同居させる植生の宣言。原型を安定IDの綴りで指すのは、`ソース種別`を`Copy`のまま保つためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 同居植生宣言 {
    pub(super) 原型の安定id: &'static str,
    pub(super) 個体数: usize,
}

/// 見本の集落へ散らす小物1種の宣言。原型を安定IDの綴りとソース相対パスの両方で持つのは、
/// 同じ1件がアセット定義の一覧(ソースの置き場を決める側)と群の指定(コンパイラへ渡す側)の両方を生むためである。
/// 2つを別の表に分けると、片方だけ足した宣言がカタログ未登録という遠い場所の失敗になる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 小物群宣言 {
    pub(super) 原型の安定id: &'static str,
    pub(super) ソース相対パス: &'static str,
    pub(super) 個体数: usize,
    pub(super) 配置様式: 配置様式,
}

/// コンパイル対象のソースが何の形式で書かれているか。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) enum ソース種別 {
    /// glTF(.gltf/.glb)で書かれたシーン。
    Gltfシーン,
    高さ格子 {
        同居植生: Option<同居植生宣言>,
    },
    /// glTFを原型として読み、決定的に生成した配置でインスタンス群を焼く。
    植生 {
        個体数: usize,
    },
    /// 同じ原型から、可視判定の検収用の固定配置と影を受ける床を焼く。
    植生可視判定,
    /// 同じ原型から、恒等でないTRSを与えた個体1体と影を受ける床を焼く。
    植生単一個体,
    /// 段を2つ持つ原型から、カメラの等距離弧へ並べた配置で個体別LODの検収用シーンを焼く。
    植生詳細段,
    /// 高さ格子を地面として焼き、宣言した種の数だけインスタンス群を同居させる。
    見本の集落 {
        群一覧: &'static [小物群宣言],
    },
}
