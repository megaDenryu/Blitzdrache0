//! コンパイル対象のソースが何の形式で書かれているかと、形式ごとに要る付随の宣言。
//! 読み方が形式ごとに違うため判別共用体で持ち、形式を1つ足すときに触る場所をここへ閉じる。
//! 宣言をカタログとコンパイル対象一覧へ写すのは`catalog`が、どの世界が何を宣言するかは`world`が持つ。

use blitz_asset_compiler::配置様式;

/// 地形チャンクへ同居させる植生の宣言。原型を安定IDの綴りで指すのは、`ソース種別`を`Copy`のまま保つためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 同居植生宣言 {
    pub(super) 原型の安定id: &'static str,
    pub(super) 個体数: usize,
}

/// 見本の集落へ散らす小物1種の宣言。原型を安定IDの綴りとソース相対パスの両方で持つのは、
/// 同じ1件がアセット定義の一覧(ソースの置き場を決める側)と群の指定(コンパイラへ渡す側)の両方を生むためである。
/// 2つを別の表に分けると、片方だけ足した宣言がカタログ未登録という遠い場所の失敗になる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 小物群宣言 {
    pub(super) 原型の安定id: &'static str,
    pub(super) ソース相対パス: &'static str,
    pub(super) 個体数: usize,
    pub(super) 配置様式: 配置様式,
}

/// 場所巡りの世界の目的地1つの大域の水平位置。天頂成分を持たないのは、目印の高さがその場所の地表高さから決まるためである。
/// 整数のメートルで持つのは、チャンク座標と局所位置への分解を床の除算と剰余で行うためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 目的地の大域の水平位置 {
    pub(super) 東メートル: i32,
    pub(super) 南メートル: i32,
}

/// コンパイル対象のソースが何の形式で書かれているか。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) enum ソース種別 {
    /// glTF(.gltf/.glb)で書かれたシーン。
    Gltfシーン,
    /// 実寸のメートルで書かれていないglTFシーン。倍率で実寸へ合わせてから焼く。
    寸法を合わせるGltfシーン { 一様倍率: f32 },
    高さ格子 {
        同居植生: Option<同居植生宣言>,
    },
    /// glTFを原型として読み、決定的に生成した配置でインスタンス群を焼く。
    植生 {
        個体数: usize,
    },
    /// 同じ原型から、可視判定の検収用の固定配置と影を受ける床を焼く。
    植生可視判定,
    /// 同じ原型から、恒等でないTRSを与えた個体1体と影を受ける床を焼く。
    植生単一個体,
    /// 同じ原型から、遠方キャスター1体と近距離対照1体と影を受ける床を焼く。影の視距離の切断が消す影を露出する負の対照である。
    植生影視距離,
    /// 段を2つ持つ原型から、カメラの等距離弧へ並べた配置で個体別LODの検収用シーンを焼く。
    植生詳細段,
    /// 高さ格子を地面として焼き、宣言した種の数だけインスタンス群を同居させる。
    見本の集落 {
        群一覧: &'static [小物群宣言],
    },
    /// 高さ格子を地面として焼き、そのチャンクに載る目的地へ目印の柱を据える。目的地が1つも載らないチャンクは地面だけになる。
    目印つき高さ格子 {
        目印の原型の安定id: &'static str,
        目的地一覧: &'static [目的地の大域の水平位置],
    },
    /// 高さ格子を庭の地面として焼き、材質見本の立体と遠景地面を据え、宣言した種の数だけインスタンス群を同居させる。
    目視見本 {
        材質見本の立体の安定id: &'static str,
        遠景地面の安定id: &'static str,
        群一覧: &'static [小物群宣言],
    },
}
