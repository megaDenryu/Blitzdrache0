//! 煙突を組み付ける2つの指示を作る工程と、煙突セグメントの綴り。壁の外面へ1段目を差し込み、その上へ
//! 2段目を積む。
//!
//! 出窓の指示(`frame_wall_ornament_instruction`)から分けるのは、煙突が飾りでなく、自分の上へ次の段を
//! 受ける部品だからである。壁の外面が受ける指示と、自分自身が受ける指示の両方を持つのはこの部品だけである。
//!
//! 綴りを別の正本へ置かないのは、煙突の綴りを読むのがこのファイルだけだからである。骨組みの綴り
//! (`frame_bay_spelling`)が独立しているのは、面の対応表と手順と複数の指示から読まれるためである。
//!
//! **1段目の様式は包含であり、面上の位置は中心・法線方向のずらしは零である。** 壁の取付面が 2.00×2.60、
//! 煙突の壁面密着面が 0.70×2.60 であり、**高さがちょうど等しい。** 包含は「差す長さが受ける長さ以下」を
//! 収まるものとして通すため、この等号が煙突を骨格の壁へ付けられるかどうかを決めている。
//!
//! **2段目の様式は一致であり、食い込ませる量は零である。** 上下の面が向かい合う隣接であり、重なる面を
//! そもそも持たないため、深度が競合する機構が無い。壁の0.02メートルとは理由から違う。
//! 参照: `_doc/設計/部品カタログと接合点.md`「壁が外面の取付面を持つ(2026-08-19、Blitzdrache0Assetsの7fc2498)」

use blitz_assembly::{据えた部品の番号, 接合の指示, 接合面上の位置, 法線方向のずらし, 部品ID};

use super::frame_bay_spelling::{壁の外面の飾り取付の接合点名, 接合点名を作る, 部品idを作る};

const 煙突セグメントの綴り: &str = "Mod_Frame_Chimney_Segment";
const 壁面密着面の綴り: &str = "壁面密着面";
const 煙突の上面の綴り: &str = "上面";
const 煙突の下面の綴り: &str = "下面";

/// 名指した壁の外面の中心へ煙突の1段目を差し込む。壁がどこにどの向きで立っているかは接合が決めており、
/// この指示は位置も角度も1つも書かない。
pub(super) fn 煙突を壁の外面へ差し込む指示を作る(親: 据えた部品の番号) -> Result<接合の指示, String> {
    Ok(接合の指示 {
        親,
        親の接合点: 壁の外面の飾り取付の接合点名()?,
        子の部品: 煙突セグメントの部品id()?,
        子の接合点: 接合点名を作る(壁面密着面の綴り)?,
        面上の位置: 接合面上の位置::中心(),
        法線方向のずらし: 法線方向のずらし::寄せない(),
    })
}

/// 名指した煙突の上面へ次の段の下面を向かい合わせる。1段ぶんの丈は上面の接合点の高さ2.60メートルが
/// 決めており、手順は高さを1つも書かない。
pub(super) fn 煙突を上へ積む指示を作る(親: 据えた部品の番号) -> Result<接合の指示, String> {
    Ok(接合の指示 {
        親,
        親の接合点: 接合点名を作る(煙突の上面の綴り)?,
        子の部品: 煙突セグメントの部品id()?,
        子の接合点: 接合点名を作る(煙突の下面の綴り)?,
        面上の位置: 接合面上の位置::中心(),
        法線方向のずらし: 法線方向のずらし::寄せない(),
    })
}

/// 1段ぶんの煙突。壁面差込と上下の積層の口を持ち、壁へ付いた上へ同じ部品を積み重ねられる。
fn 煙突セグメントの部品id() -> Result<部品ID, String> {
    部品idを作る(煙突セグメントの綴り)
}
