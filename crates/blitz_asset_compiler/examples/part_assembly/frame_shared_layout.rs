//! 骨格方式の手順が共有する指示の並びと、その並びの中で部品が受け取る番号。壁をはめた1棟ぶん・2段に積んだ
//! 骨格の両階ぶん・屋根と床と出窓まで載せた家1棟ぶんの3つを持つ。
//!
//! **後の手順が前の並びをそのまま使い、末尾へ自分の指示を足すだけなのは、Blender側の正解表がそういう関係で
//! 作られているからである。** 壁の割り当ては屋根の有無でも煙突の有無でも変わらない。手順ごとに指示の並びを
//! 写して書くと、壁の割り当てを片方だけ直した食い違いが、煙突と無関係な位置の食い違いとして現れる。
//!
//! **番号を答える口をここへ置くのは、並びと番号が同じ理由で動くためである。** 壁の並べ方を変えると背面の壁と
//! 右面の壁の番号が動き、家の並びへ1件足すと煙突の番号が動く。手順の側が番号を直に書くと、直す先が散る。
//!
//! 手順(`frame_recipe`)から分けるのは、この並びが複数の手順から呼ばれる材料だからである。呼び出し側は
//! 中身を知らずに「1棟ぶんの壁」「屋根つきの家1棟ぶん」として受け取り、その先へ自分の指示を足す。

use blitz_assembly::{据えた部品の番号, 接合の指示};

use super::frame_bay_face::ベイの面::{右面, 左面, 正面, 背面};
use super::frame_bay_instruction::{
    壁をはめる指示を作る, 屋根を載せる指示を作る, 床を張る指示を作る, 骨格を上へ積む指示を作る
};
use super::frame_bay_spelling::はめる壁の種類::{平壁, 扉枠付きの壁, 窓壁};
use super::frame_wall_ornament_instruction::出窓を壁の外面へ差し込む指示を作る;

/// 正面へ扉枠付きの壁、背面と右面へ平壁、左面へ窓壁をはめる。**どの壁も親は根の骨格である。**
/// 骨格は壁を介して他の部品を受けない。
pub(super) fn 壁をはめた一間四方の骨格の指示一覧() -> Result<Vec<接合の指示>, String> {
    let 根 = 据えた部品の番号::根();
    Ok(vec![
        壁をはめる指示を作る(根, 正面, 扉枠付きの壁)?,
        壁をはめる指示を作る(根, 背面, 平壁)?,
        壁をはめる指示を作る(根, 左面, 窓壁)?,
        壁をはめる指示を作る(根, 右面, 平壁)?,
    ])
}

/// 骨格を2段積み、両階の4面すべてへ壁を入れる。2階は正面を窓壁にして、階で違う壁が入ることを絵に出す。
pub(super) fn 二段に積んだ骨格の指示一覧() -> Result<Vec<接合の指示>, String> {
    let 一階 = 据えた部品の番号::根();
    let 二階 = 二階の番号();
    Ok(vec![
        骨格を上へ積む指示を作る(一階)?,
        壁をはめる指示を作る(一階, 正面, 扉枠付きの壁)?,
        壁をはめる指示を作る(一階, 左面, 窓壁)?,
        壁をはめる指示を作る(一階, 背面, 平壁)?,
        壁をはめる指示を作る(一階, 右面, 平壁)?,
        壁をはめる指示を作る(二階, 正面, 窓壁)?,
        壁をはめる指示を作る(二階, 左面, 窓壁)?,
        壁をはめる指示を作る(二階, 背面, 平壁)?,
        壁をはめる指示を作る(二階, 右面, 平壁)?,
    ])
}

/// 壁をはめた1棟へ床を1枚張り、上へ切妻屋根を載せ、背面の平壁の外面へ出窓を差し込む。
/// **床と屋根の親は根の骨格であり、出窓の親は背面の壁である。** 煙突を足した家がこの並びへ煙突を継ぐ。
pub(super) fn 屋根を載せた一間四方の家の指示一覧() -> Result<Vec<接合の指示>, String> {
    let mut 指示一覧 = 壁をはめた一間四方の骨格の指示一覧()?;
    指示一覧.push(床を張る指示を作る(据えた部品の番号::根())?);
    指示一覧.push(屋根を載せる指示を作る(据えた部品の番号::根())?);
    指示一覧.push(出窓を壁の外面へ差し込む指示を作る(背面の壁の番号())?);
    Ok(指示一覧)
}

/// 1棟ぶんの壁の並びで背面の平壁が受け取る番号。根が0で、正面・背面・左面・右面の順に積むため2になる。
/// **飾りの親を番号で名指す唯一の口をここへ置くのは、壁の並べ方を変えたときに直す先を1つに保つためである。**
pub(super) fn 背面の壁の番号() -> 据えた部品の番号 {
    据えた部品の番号::番号から生成する(2)
}

/// 同じ並びで右面の平壁が受け取る番号。正面・背面・左面・右面の順に積むため4になる。
pub(super) fn 右面の壁の番号() -> 据えた部品の番号 {
    据えた部品の番号::番号から生成する(4)
}

/// 屋根を載せた家の並びへ煙突を継いだとき、1段目の煙突が受け取る番号。
/// 骨格と壁4枚と床と屋根と出窓の8件の後に据わるため8になる。
pub(super) fn 一段目の煙突の番号() -> 据えた部品の番号 {
    据えた部品の番号::番号から生成する(8)
}

/// 2段積みの手順で2階の骨格が受け取る番号。積む指示が最初の1件であるため1になる。
pub(super) fn 二階の番号() -> 据えた部品の番号 {
    据えた部品の番号::番号から生成する(1)
}
