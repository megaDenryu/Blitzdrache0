//! 骨格方式の手順が共有する壁の割り当て。壁をはめた1棟ぶんと、2段に積んだ骨格の両階ぶんの指示の並びを持つ。
//!
//! **屋根つきの家がこの並びをそのまま使い、末尾へ床と屋根を足すだけなのは、Blender側の正解表がそういう関係で
//! 作られているからである。** 壁の割り当ては屋根の有無で変わらない。手順ごとに指示の並びを写して書くと、
//! 壁の割り当てを片方だけ直した食い違いが、屋根や床と無関係な位置の食い違いとして現れる。
//!
//! 手順(`frame_recipe`)から分けるのは、この並びが2つの手順から呼ばれる材料だからである。呼び出し側は
//! 中身を知らずに「1棟ぶんの壁」「2段ぶんの壁」として受け取り、その先へ自分の指示を足す。

use blitz_assembly::{据えた部品の番号, 接合の指示};

use super::frame_bay_face::ベイの面::{右面, 左面, 正面, 背面};
use super::frame_bay_instruction::{壁をはめる指示を作る, 骨格を上へ積む指示を作る};
use super::frame_bay_spelling::はめる壁の種類::{平壁, 扉枠付きの壁, 窓壁};

/// 正面へ扉枠付きの壁、背面と右面へ平壁、左面へ窓壁をはめる。**どの壁も親は根の骨格である。**
/// 骨格は壁を介して他の部品を受けない。
pub(super) fn 壁をはめた一間四方の骨格の指示一覧() -> Result<Vec<接合の指示>, String> {
    let 根 = 据えた部品の番号::根();
    Ok(vec![
        壁をはめる指示を作る(根, 正面, 扉枠付きの壁)?,
        壁をはめる指示を作る(根, 背面, 平壁)?,
        壁をはめる指示を作る(根, 左面, 窓壁)?,
        壁をはめる指示を作る(根, 右面, 平壁)?,
    ])
}

/// 骨格を2段積み、両階の4面すべてへ壁を入れる。2階は正面を窓壁にして、階で違う壁が入ることを絵に出す。
pub(super) fn 二段に積んだ骨格の指示一覧() -> Result<Vec<接合の指示>, String> {
    let 一階 = 据えた部品の番号::根();
    let 二階 = 二階の番号();
    Ok(vec![
        骨格を上へ積む指示を作る(一階)?,
        壁をはめる指示を作る(一階, 正面, 扉枠付きの壁)?,
        壁をはめる指示を作る(一階, 左面, 窓壁)?,
        壁をはめる指示を作る(一階, 背面, 平壁)?,
        壁をはめる指示を作る(一階, 右面, 平壁)?,
        壁をはめる指示を作る(二階, 正面, 窓壁)?,
        壁をはめる指示を作る(二階, 左面, 窓壁)?,
        壁をはめる指示を作る(二階, 背面, 平壁)?,
        壁をはめる指示を作る(二階, 右面, 平壁)?,
    ])
}

/// 2段積みの手順で2階の骨格が受け取る番号。積む指示が最初の1件であるため1になる。
pub(super) fn 二階の番号() -> 据えた部品の番号 {
    据えた部品の番号::番号から生成する(1)
}
