//! 骨格方式の5種の接合の指示を作る工程。壁をはめる・骨格を上へ積む・隣のベイを横へ継ぐ・屋根を載せる・
//! 床を張る の5つである。
//!
//! 綴りの正本(`frame_bay_spelling`)と分けるのは、変わる理由が違うためである。綴りはBlender側が部品の名前を
//! 変えると変わり、食い込ませる量は絵の目視が決める。
//!
//! **どの指示も一致の様式であるため、面上の位置は中心のほかに置きようがない。**
//!
//! 食い込ませる量が壁だけ0.02メートルで、積層と継ぎと屋根と床が0なのは、深度が競合する機構が違うためである。
//! 壁を寄せないと骨格の柱と梁の外面(±1.00)と壁の背面がちょうど同一平面になって重なる。積層と継ぎと屋根と床は
//! 面が向かい合う隣接であり、柱の外面が上下や左右へ連続するだけで、重なる面をそもそも持たない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格の上下積層とベイの継ぎ口(2026-08-19 追加)」

use blitz_assembly::{据えた部品の番号, 接合の指示, 接合面上の位置, 法線方向のずらし};
use blitz_math::メートル;

use super::frame_bay_face::ベイの面;
use super::frame_bay_spelling::{
    はめる壁の種類, 切妻屋根の部品id, 壁の外枠の接合点名, 屋根の下面の接合点名, 床のはめ口の接合点名, 床の外枠の接合点名, 床板の部品id,
    骨格の上面の接合点名, 骨格の下面の接合点名, 骨格の部品id,
};

/// 壁を骨格の面へ食い込ませる量。部品の寸法から導出できない配置の決定であり、2026-08-18の親の目視が確定した。
const 壁を骨格の面へ食い込ませる量: f32 = 0.02;

pub(super) fn 壁をはめる指示を作る(
    親: 据えた部品の番号, 面: ベイの面, 壁: はめる壁の種類
) -> Result<接合の指示, String> {
    let 寄せ = 法線方向のずらし::食い込ませる量から生成する(メートル::生成する(壁を骨格の面へ食い込ませる量)).map_err(|誤り| 誤り.to_string())?;
    Ok(接合の指示 {
        親,
        親の接合点: 面.壁のはめ口の接合点名()?,
        子の部品: 壁.部品id()?,
        子の接合点: 壁の外枠の接合点名()?,
        面上の位置: 接合面上の位置::中心(),
        法線方向のずらし: 寄せ,
    })
}

/// 骨格の上面へ次の階の骨格の下面を向かい合わせる。階高は骨格の上面の高さ2.60メートルが決めており、
/// 手順は高さを1つも書かない。
pub(super) fn 骨格を上へ積む指示を作る(親: 据えた部品の番号) -> Result<接合の指示, String> {
    Ok(接合の指示 {
        親,
        親の接合点: 骨格の上面の接合点名()?,
        子の部品: 骨格の部品id()?,
        子の接合点: 骨格の下面の接合点名()?,
        面上の位置: 接合面上の位置::中心(),
        法線方向のずらし: 法線方向のずらし::寄せない(),
    })
}

/// 骨格の上面へ屋根の下面を向かい合わせる。屋根が載る高さは骨格の上面の高さが決めており、手順は高さを1つも書かない。
/// **屋根は骨格を上へ積むのとまったく同じ対(上面積層と下面積層)で載る。** 種別を新設していない。
pub(super) fn 屋根を載せる指示を作る(親: 据えた部品の番号) -> Result<接合の指示, String> {
    Ok(接合の指示 {
        親,
        親の接合点: 骨格の上面の接合点名()?,
        子の部品: 切妻屋根の部品id()?,
        子の接合点: 屋根の下面の接合点名()?,
        面上の位置: 接合面上の位置::中心(),
        法線方向のずらし: 法線方向のずらし::寄せない(),
    })
}

/// 骨格の床のはめ口へ床板の外枠を向かい合わせる。床が張られる高さは土台の梁の上面0.16メートルが決めており、
/// 手順は高さを1つも書かない。**上面積層と下面積層でなく床の対で噛み合わせるのは、積層を流用すると
/// 床のはめ口へ骨格の下面が入る組み方を種別で弾けないためである。**
pub(super) fn 床を張る指示を作る(親: 据えた部品の番号) -> Result<接合の指示, String> {
    Ok(接合の指示 {
        親,
        親の接合点: 床のはめ口の接合点名()?,
        子の部品: 床板の部品id()?,
        子の接合点: 床の外枠の接合点名()?,
        面上の位置: 接合面上の位置::中心(),
        法線方向のずらし: 法線方向のずらし::寄せない(),
    })
}

/// 骨格の1つの面の継ぎ口へ、隣の骨格の反対側の面の継ぎ口を向かい合わせる。ベイの継ぎ口は相互であり、
/// 親も子も同じ種別を名乗る。横へ進む量は2つの継ぎ口の位置(±1.00メートル)が決めており、手順は距離を書かない。
pub(super) fn 隣のベイを横へ継ぐ指示を作る(
    親: 据えた部品の番号,
    親の面: ベイの面,
    子の面: ベイの面,
) -> Result<接合の指示, String> {
    Ok(接合の指示 {
        親,
        親の接合点: 親の面.ベイの継ぎ口の接合点名()?,
        子の部品: 骨格の部品id()?,
        子の接合点: 子の面.ベイの継ぎ口の接合点名()?,
        面上の位置: 接合面上の位置::中心(),
        法線方向のずらし: 法線方向のずらし::寄せない(),
    })
}
