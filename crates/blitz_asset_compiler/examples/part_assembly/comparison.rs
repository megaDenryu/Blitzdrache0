//! 展開の結果と正解表の突き合わせ。担当するのは、部品ごとの姿勢の差を測って報告の形にすることである。
//!
//! 平行移動と回転の両方を見る。**平行移動だけでは「向きが90度ずれている」を捉えられない。**
//! 回転はクォータニオンの符号違いを同一視する。同じ回転が2つの綴りで表せるためである。
//!
//! 姿勢1件の隔たりの測り方と許容差は`tolerance`が持つ。どの部品の配置へどの正解の行を当てるかは`assignment`が持つ。

use blitz_assembly::部品ごとの配置表;
use blitz_asset_compiler::正解表;

use super::assignment::平行移動が近い順に割り当てる;
use super::tolerance::{最大の差, 符号違いを同一視した最大の差, 許容差を求める};

pub struct 突き合わせの結果 {
    pub 一致した件数: usize,
    pub 食い違いの行一覧: Vec<String>,
    pub 正解表に無い部品一覧: Vec<String>,
    /// 正解表に載っているのに、この手順では展開していない部品。突き合わせの対象外であることを報告へ出す。
    pub 展開していない部品一覧: Vec<String>,
}

impl 突き合わせの結果 {
    pub fn 合格か(&self) -> bool {
        self.食い違いの行一覧.is_empty() && self.正解表に無い部品一覧.is_empty()
    }

    pub fn 配置表と正解表を突き合わせる(配置表: &部品ごとの配置表, 正解表: &正解表) -> Self {
        let mut 結果 = Self {
            一致した件数: 0,
            食い違いの行一覧: Vec::new(),
            正解表に無い部品一覧: Vec::new(),
            展開していない部品一覧: Vec::new(),
        };
        for 項目 in 配置表.項目一覧() {
            let 綴り = 項目.識別子().綴り();
            let 正解一覧 = 正解表.部品で全件引く(綴り);
            if 正解一覧.is_empty() {
                結果.正解表に無い部品一覧.push(綴り.to_string());
                continue;
            }
            let 配置一覧: Vec<([f32; 3], [f32; 4])> = 項目.配置一覧().iter().map(|配置| (配置.平行移動(), 配置.回転())).collect();
            for 組 in 平行移動が近い順に割り当てる(&配置一覧, &正解一覧) {
                let Some(正解) = 組.正解 else {
                    結果.食い違いの行一覧.push(format!(
                        "  {綴り}: 据えた件数が正解表の{}件を超える。平行移動{:?}に割り当てる行が残っていない",
                        正解一覧.len(),
                        組.得た移動
                    ));
                    continue;
                };
                結果.姿勢1件を突き合わせる(綴り, 組.得た移動, 組.得た回転, 正解.平行移動, 正解.回転);
            }
            結果.正解表の余りを数える(綴り, 正解一覧.len(), 配置一覧.len());
        }
        結果.展開していない部品を数え上げる(配置表, 正解表);
        結果
    }

    /// 展開した部品の一覧に無い正解表の行を集める。数だけを見て「不一致」と読み違えないための項目である。
    fn 展開していない部品を数え上げる(&mut self, 配置表: &部品ごとの配置表, 正解表: &正解表) {
        for 姿勢 in 正解表.姿勢一覧() {
            let 展開したか = 配置表.項目一覧().iter().any(|項目| 項目.識別子().綴り() == 姿勢.部品の識別子);
            if !展開したか {
                self.展開していない部品一覧.push(姿勢.部品の識別子.clone());
            }
        }
    }

    /// 正解表に在るのに据えられていない行を食い違いとして出す。件数が足りないことは、規則が部品を1つ落とした
    /// ことを意味し、割り当ての側からは「余った行」としてしか見えない。
    fn 正解表の余りを数える(&mut self, 綴り: &str, 正解の件数: usize, 据えた件数: usize) {
        if 据えた件数 >= 正解の件数 {
            return;
        }
        self.食い違いの行一覧
            .push(format!("  {綴り}: 据えた件数{据えた件数}が正解表の{正解の件数}件に足りない"));
    }

    fn 姿勢1件を突き合わせる(
        &mut self, 綴り: &str, 得た移動: [f32; 3], 得た回転: [f32; 4], 正解の移動: [f32; 3], 正解の回転: [f32; 4]
    ) {
        let 移動の差 = 最大の差(&得た移動, &正解の移動);
        let 移動の許容差 = 許容差を求める(&得た移動, &正解の移動);
        let 回転の差 = 符号違いを同一視した最大の差(&得た回転, &正解の回転);
        if 移動の差 <= 移動の許容差 && 回転の差 <= 許容差を求める(&得た回転, &正解の回転) {
            self.一致した件数 += 1;
            return;
        }
        self.食い違いの行一覧.push(format!(
            "  {綴り}: 平行移動 得た{得た移動:?} 正解{正解の移動:?} 差{移動の差:.6} / 回転 得た{得た回転:?} 正解{正解の回転:?} 差{回転の差:.6}"
        ));
    }
}
