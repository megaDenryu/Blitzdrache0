//! 一間四方の骨格へ壁を4枚はめた小屋の組み立て手順。どの面へどの壁をはめるかを宣言として書く。
//!
//! **規則でなく手順を書くのは、この突き合わせが見るものが規則の選択でないからである。** ここで確かめるのは
//! 接合の計算がBlender側の配置と一致することであり、右面へ何を入れるかを種で引くのは別の関心事である。
//! 正解表は「4面すべてに壁をはめた1棟」であるため、その組み立てをそのまま書く。
//!
//! **4つのはめ口は向きだけが違い上方向がどれも天頂である。** したがって壁は天頂軸まわりだけに回り、
//! 回る量は接合が向かい合う枠から導く。手順は角度を1つも書かない。
//!
//! 食い込ませる量0.02メートルは、部品の寸法から導出できない配置の決定である。零にすると骨格の柱と梁の外面と
//! 壁の背面がちょうど同一平面になり、深度が競合する。Blender側もこの量で正解表を書き出している。
//! 参照: `_doc/設計/部品カタログと接合点.md`「段7: 一間四方の骨格へ壁をはめる」

use blitz_assembly::{
    据えた部品の番号, 接合の指示, 接合点名, 接合面上の位置, 法線方向のずらし, 組み立て手順, 部品ID
};
use blitz_math::メートル;

const 骨格: &str = "Mod_Frame_Bay_Single";
const 平壁: &str = "Mod_Wall_HalfTimber_Solid";
const 窓壁: &str = "Mod_Wall_HalfTimber_Window";
const 扉枠付きの壁: &str = "Mod_Wall_HalfTimber_DoorFrame";

/// 壁3種が共通で持つ、骨格のはめ口と噛み合う接合点の名前。
const 壁の外枠: &str = "壁の外枠";

/// 骨格の面へ壁を食い込ませる量。
const 食い込ませる量: f32 = 0.02;

/// 正面へ扉枠付きの壁、背面と右面へ平壁、左面へ窓壁をはめる。据えた番号は根の骨格が0であり、
/// 指示を1つ積むごとに1つ増える。**どの壁も親は根の骨格である。** 骨格は壁を介して他の部品を受けない。
pub fn 壁をはめた一間四方の骨格の手順() -> Result<組み立て手順, String> {
    let 指示一覧 = vec![
        はめる("正面のはめ口", 扉枠付きの壁)?,
        はめる("背面のはめ口", 平壁)?,
        はめる("左面のはめ口", 窓壁)?,
        はめる("右面のはめ口", 平壁)?,
    ];
    Ok(組み立て手順::根と指示から生成する(識別子(骨格)?, 指示一覧))
}

/// はめ口1つへ壁を1枚はめる指示。一致の様式であるため面上の位置は中心のほかに置きようがない。
fn はめる(はめ口: &str, 壁: &str) -> Result<接合の指示, String> {
    let 寄せ = 法線方向のずらし::食い込ませる量から生成する(メートル::生成する(食い込ませる量)).map_err(|誤り| 誤り.to_string())?;
    Ok(接合の指示 {
        親: 据えた部品の番号::根(),
        親の接合点: 名前(はめ口)?,
        子の部品: 識別子(壁)?,
        子の接合点: 名前(壁の外枠)?,
        面上の位置: 接合面上の位置::中心(),
        法線方向のずらし: 寄せ,
    })
}

fn 名前(綴り: &str) -> Result<接合点名, String> {
    接合点名::生成する(綴り).map_err(|誤り| 誤り.to_string())
}

fn 識別子(綴り: &str) -> Result<部品ID, String> {
    部品ID::生成する(綴り).map_err(|誤り| 誤り.to_string())
}
