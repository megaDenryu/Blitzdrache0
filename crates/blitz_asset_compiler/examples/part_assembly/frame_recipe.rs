//! 骨格方式の5つの組み立て手順。壁をはめた1棟・2段に積んだ骨格・横に2ベイ継いだ骨格と、そのうち2つへ床と屋根を
//! 足した家を、どれも宣言として書く。共有する壁の割り当ては`frame_shared_layout`が持つ。
//!
//! **規則でなく手順を書くのは、この突き合わせが見るものが規則の選択でないからである。** ここで確かめるのは
//! 接合の計算がBlender側の配置と一致することであり、どの面へ何を入れるかを種で引くのは別の関心事である。
//!
//! **床を持つのは家2件だけである。** 2段積みと2ベイの見本は骨格そのものの継ぎ方を見るためのものであり、
//! Blender側の正解表もその2件へ床を含めていない。
//!
//! **4つのはめ口も4つの継ぎ口も向きだけが違い上方向がどれも天頂である。** したがって壁も隣のベイも天頂軸まわり
//! だけに回り、回る量は接合が向かい合う枠から導く。手順は角度も距離も高さも1つも書かない。
//!
//! 継いだ面へ壁を入れないのは、壁のはめ口とベイの継ぎ口が同じ物理面へ重ねて宣言されているためである。
//! 両方を使うと、壁と隣のベイが同じ面へ二重に入る。**この排他は規則の責務であり、接合の契約は課さない。**
//! 参照: `_doc/設計/部品カタログと接合点.md`「段7: 一間四方の骨格へ壁をはめる」

use blitz_assembly::{据えた部品の番号, 接合の指示, 組み立て手順};

use super::frame_bay_face::ベイの面::{右面, 左面, 正面, 背面};
use super::frame_bay_instruction::{
    壁をはめる指示を作る, 屋根を載せる指示を作る, 床を張る指示を作る, 隣のベイを横へ継ぐ指示を作る
};
use super::frame_bay_spelling::はめる壁の種類::{平壁, 扉枠付きの壁, 窓壁};
use super::frame_bay_spelling::骨格の部品id;
use super::frame_shared_layout::{二段に積んだ骨格の指示一覧, 二階の番号, 壁をはめた一間四方の骨格の指示一覧};

/// 正面へ扉枠付きの壁、背面と右面へ平壁、左面へ窓壁をはめた1棟。床も屋根も持たない。
pub fn 壁をはめた一間四方の骨格の手順() -> Result<組み立て手順, String> {
    骨格を根にした手順を組む(壁をはめた一間四方の骨格の指示一覧()?)
}

/// 壁をはめた1棟へ床を1枚張り、上へ切妻屋根を載せた家。床も屋根も親は根の骨格である。
pub fn 屋根を載せた一間四方の家の手順() -> Result<組み立て手順, String> {
    let mut 指示一覧 = 壁をはめた一間四方の骨格の指示一覧()?;
    指示一覧.push(床を張る指示を作る(据えた部品の番号::根())?);
    指示一覧.push(屋根を載せる指示を作る(据えた部品の番号::根())?);
    骨格を根にした手順を組む(指示一覧)
}

/// 骨格を2段積み、両階の4面すべてへ壁を入れる。床も屋根も持たない。
pub fn 二段に積んだ骨格の手順() -> Result<組み立て手順, String> {
    骨格を根にした手順を組む(二段に積んだ骨格の指示一覧()?)
}

/// 2段に積んだ骨格へ階ごとに床を1枚ずつ張り、上へ切妻屋根を載せた家。**床は骨格ごとに1枚であり、
/// 2階の床は2階の骨格が親である。** 屋根の親も2階の骨格であり、Y成分は階高の2段ぶんになる。
pub fn 屋根を載せた二段の家の手順() -> Result<組み立て手順, String> {
    let mut 指示一覧 = 二段に積んだ骨格の指示一覧()?;
    指示一覧.push(床を張る指示を作る(据えた部品の番号::根())?);
    指示一覧.push(床を張る指示を作る(二階の番号())?);
    指示一覧.push(屋根を載せる指示を作る(二階の番号())?);
    骨格を根にした手順を組む(指示一覧)
}

/// 骨格を横に2ベイ継ぎ、継いだ面(左のベイの右面と右のベイの左面)を除く6面へ壁を入れる。
pub fn 横に二ベイ継いだ骨格の手順() -> Result<組み立て手順, String> {
    let 左のベイ = 据えた部品の番号::根();
    let 右のベイ = 据えた部品の番号::番号から生成する(1);
    骨格を根にした手順を組む(vec![
        隣のベイを横へ継ぐ指示を作る(左のベイ, 右面, 左面)?,
        壁をはめる指示を作る(左のベイ, 正面, 扉枠付きの壁)?,
        壁をはめる指示を作る(左のベイ, 左面, 窓壁)?,
        壁をはめる指示を作る(左のベイ, 背面, 平壁)?,
        壁をはめる指示を作る(右のベイ, 正面, 窓壁)?,
        壁をはめる指示を作る(右のベイ, 右面, 平壁)?,
        壁をはめる指示を作る(右のベイ, 背面, 平壁)?,
    ])
}

fn 骨格を根にした手順を組む(指示一覧: Vec<接合の指示>) -> Result<組み立て手順, String> {
    Ok(組み立て手順::根と指示から生成する(骨格の部品id()?, 指示一覧))
}
