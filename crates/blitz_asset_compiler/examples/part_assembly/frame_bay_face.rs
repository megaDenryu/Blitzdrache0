//! 骨格の4つの側面。1つの面が壁のはめ口とベイの継ぎ口を重ねて持ち、どちらか一方だけを使う。
//!
//! **面が2つの口の名前を答えるのは、同じ物理面へ2つの種別が重ねて宣言されているためである。** 面を選べば
//! 両方の綴りが決まるため、正面の壁を背面の継ぎ口へ繋ぐ取り違えを手順が書けない。綴りを手順の側が直に書くと、
//! その取り違えが「宙に浮いた部品」という遠い場所の失敗になる。
//!
//! 部品と上下の口の綴りの正本(`frame_bay_spelling`)から分けるのは、この型が持つのが綴りの表でなく
//! 面と口の対応だからである。面が増えるのは骨格の形が変わったときであり、綴りが変わるのはBlender側が
//! 名前を改めたときである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「役割「相互」」

use blitz_assembly::接合点名;

use super::frame_bay_spelling::接合点名を作る;

#[derive(Debug, Clone, Copy)]
pub(super) enum ベイの面 {
    正面,
    背面,
    左面,
    右面,
}

impl ベイの面 {
    pub(super) fn 壁のはめ口の接合点名(self) -> Result<接合点名, String> {
        接合点名を作る(match self {
            Self::正面 => "正面のはめ口",
            Self::背面 => "背面のはめ口",
            Self::左面 => "左面のはめ口",
            Self::右面 => "右面のはめ口",
        })
    }

    pub(super) fn ベイの継ぎ口の接合点名(self) -> Result<接合点名, String> {
        接合点名を作る(match self {
            Self::正面 => "正面の継ぎ口",
            Self::背面 => "背面の継ぎ口",
            Self::左面 => "左面の継ぎ口",
            Self::右面 => "右面の継ぎ口",
        })
    }
}
