//! 壁の外面へ飾りを差し込む指示を作る工程。骨格の口が受ける5種の指示(`frame_bay_instruction`)から分けるのは、
//! 親になる部品が違うためである。あちらはどれも骨格の口が受け、こちらは壁の外面が受ける。
//!
//! **骨格方式で壁が何かを受けるのはこれが初めてである。** 段7の時点では骨格が壁を受けるだけで、壁は葉であった。
//! 出窓が付くことで、骨格から壁へ、壁から飾りへと2段に伸びる。
//!
//! **様式は包含であり、面上の位置は中心・法線方向のずらしは零である。** 壁の取付面が 2.00×2.60、出窓の差込口が
//! 1.80×1.40 であるため包含の判定が通る。零で寄せないのは、出窓の差込口が部品の背面の表面にあり、
//! 向かい合わせるだけで外面へ密着するというBlender側の申告に従うためである。**この判断の網は絵の目視だけである。**
//! 浮きやめり込みが見えたら値を改める。
//! 参照: `_doc/設計/部品カタログと接合点.md`「壁が外面の取付面を持つ(2026-08-19、Blitzdrache0Assetsの7fc2498)」

use blitz_assembly::{据えた部品の番号, 接合の指示, 接合面上の位置, 法線方向のずらし};

use super::frame_bay_spelling::{出窓の壁面差込口の接合点名, 出窓の部品id, 壁の外面の飾り取付の接合点名};

/// 名指した壁の外面の中心へ出窓を差し込む。壁がどこにどの向きで立っているかは接合が決めており、
/// この指示は位置も角度も1つも書かない。
pub(super) fn 出窓を壁の外面へ差し込む指示を作る(親: 据えた部品の番号) -> Result<接合の指示, String> {
    Ok(接合の指示 {
        親,
        親の接合点: 壁の外面の飾り取付の接合点名()?,
        子の部品: 出窓の部品id()?,
        子の接合点: 出窓の壁面差込口の接合点名()?,
        面上の位置: 接合面上の位置::中心(),
        法線方向のずらし: 法線方向のずらし::寄せない(),
    })
}
