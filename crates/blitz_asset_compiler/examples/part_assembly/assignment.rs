//! 展開した配置と正解表の行を1対1で対応づける工程。受け取るのは同じ部品IDの配置の並びと正解の並び、
//! 返すのは配置ごとに割り当てた正解である。
//!
//! **同じ部品が何度も現れる正解表があるため、部品IDだけでは対応が決まらない。** 木は幹を3節・枝を3本・
//! 葉房を4つ据えるため、部品IDで引くと全部が表の先頭の行と比べられ、正しい組み立てでも食い違いとして出る。
//!
//! 据えた順と表の並び順で対応づけない。**順は組み立ての手順とBlender側の書き出しの都合で決まり、
//! どちらが変わっても絵は変わらない。** 順を要求すると、絵の破れでないものが不合格になる。
//!
//! 代わりに平行移動が最も近い未使用の行を割り当てる。取り違えを許さないのは、割り当てた後で
//! 突き合わせが許容差を課すためである。全件が1対1で許容差以内に収まって初めて合格になる。

use blitz_asset_compiler::正解の姿勢;
use blitz_engine::個体配置;

/// 配置1件と、その配置へ割り当てた正解。相手が尽きた配置は正解を持たない。
pub struct 割り当てた組<'正解> {
    pub 得た配置: 個体配置,
    pub 正解: Option<&'正解 正解の姿勢>,
}

/// 同じ部品IDの配置の並びへ、同じ部品IDの正解の並びを1対1で割り当てる。
pub fn 平行移動が近い順に割り当てる<'正解>(
    配置一覧: &[個体配置],
    正解一覧: &[&'正解 正解の姿勢],
) -> Vec<割り当てた組<'正解>> {
    let mut 使用済み = vec![false; 正解一覧.len()];
    配置一覧
        .iter()
        .map(|配置| 割り当てた組 {
            得た配置: *配置,
            正解: 最も近い未使用を選ぶ(配置.平行移動(), 正解一覧, &mut 使用済み),
        })
        .collect()
}

/// 未使用の正解のうち、平行移動の隔たりが最も小さいものを選んで使用済みにする。
fn 最も近い未使用を選ぶ<'正解>(
    得た移動: [f32; 3],
    正解一覧: &[&'正解 正解の姿勢],
    使用済み: &mut [bool],
) -> Option<&'正解 正解の姿勢> {
    let mut 最良: Option<(usize, f32)> = None;
    for (添字, 正解) in 正解一覧.iter().enumerate() {
        if 使用済み.get(添字).copied().unwrap_or(true) {
            continue;
        }
        let 隔たり = 二乗の隔たり(得た移動, 正解.平行移動);
        if 最良.is_none_or(|(_, 最小)| 隔たり < 最小) {
            最良 = Some((添字, 隔たり));
        }
    }
    let (添字, _) = 最良?;
    if let Some(印) = 使用済み.get_mut(添字) {
        *印 = true;
    }
    正解一覧.get(添字).copied()
}

/// 平方根を取らないのは、大小を比べるだけであり根が順序を変えないためである。
fn 二乗の隔たり(左: [f32; 3], 右: [f32; 3]) -> f32 {
    左.iter().zip(右).map(|(左の成分, 右の成分)| (左の成分 - 右の成分).powi(2)).sum()
}
