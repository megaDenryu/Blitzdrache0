//! 突き合わせと接触の検査の結果を、読み手が見る文面へ写す工程。担当するのは並べる項目と綴りだけである。
//!
//! 突き合わせた件数を正解表の件数と別に出すのは、「7件中4件一致」と読むと3件が食い違ったように見えるためである。
//! 展開していない部品は突き合わせの対象ではなく、食い違いでもない。

use blitz_asset_compiler::正解表;

use super::comparison::突き合わせの結果;
use super::contact_check::接触の検査結果;

pub fn 結果を報告する(正解表: &正解表, 結果: &突き合わせの結果) -> bool {
    println!("=== 組み立ての突き合わせ: {} ===", 正解表.組み立ての識別子());
    let 突き合わせた件数 = 結果.一致した件数 + 結果.食い違いの行一覧.len();
    println!(
        "正解表の姿勢{}件のうち{}件を突き合わせ、一致{}件・食い違い{}件",
        正解表.姿勢一覧().len(),
        突き合わせた件数,
        結果.一致した件数,
        結果.食い違いの行一覧.len()
    );
    if !結果.展開していない部品一覧.is_empty() {
        println!(
            "正解表にあるが、この手順では展開していない部品: {}",
            結果.展開していない部品一覧.join("・")
        );
    }
    if !結果.正解表に無い部品一覧.is_empty() {
        println!("正解表に載っていない部品: {}", 結果.正解表に無い部品一覧.join("・"));
    }
    if 結果.食い違いの行一覧.is_empty() {
        println!("判定: 全件が正解表と一致した");
        return 結果.合格か();
    }
    println!("食い違い{}件:", 結果.食い違いの行一覧.len());
    for 行 in &結果.食い違いの行一覧 {
        println!("{行}");
    }
    println!("判定: 正解表と食い違う配置がある");
    false
}

/// 組み上げた部品が親と接しているかの報告。貫入と包含を見ない理由は`contact_check`が持つ。
pub fn 接触を報告する(接触: &接触の検査結果) -> bool {
    println!("親と接している接合{}件", 接触.接している件数);
    if 接触.離れている行一覧.is_empty() {
        println!("判定: 宙に浮いた部品は無い");
        return true;
    }
    println!("親から離れている接合{}件:", 接触.離れている行一覧.len());
    for 行 in &接触.離れている行一覧 {
        println!("{行}");
    }
    println!("判定: 親から離れた部品がある");
    false
}
