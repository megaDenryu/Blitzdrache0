//! 姿勢1件の突き合わせ。受け取るのは展開が求めた配置と正解表の1行、返すのは許容差を超えた食い違いの文面である。
//!
//! **平行移動と回転と倍率の3つを見る。** 平行移動だけでは「向きが90度ずれている」を捉えられず、
//! 平行移動と回転だけでは「大きさが違う部品を同じ位置へ据えた」を捉えられない。倍率を見ないと、
//! 一致の様式が導いた比(木の幹が節ごとに細くなる比)も、包含の様式が親から引き継ぐ比も、
//! Blender側と突き合わされないまま通る。
//!
//! 突き合わせの集計(`comparison`)から分けるのは、担当が違うためである。あちらはどの配置にどの行を当てるかを
//! 決めて数を集め、こちらは当たった1組の隔たりだけを測る。隔たりの測り方と許容差そのものは`tolerance`が持つ。

use blitz_asset_compiler::正解の姿勢;
use blitz_engine::個体配置;

use super::tolerance::{最大の差, 符号違いを同一視した最大の差, 許容差を求める};

/// 許容差を超えていれば食い違いの1行を返す。3つとも収まっていれば何も返さない。
pub(super) fn 姿勢1件の食い違いを測る(綴り: &str, 得た配置: &個体配置, 正解: &正解の姿勢) -> Option<String> {
    let 移動の差 = 最大の差(&得た配置.平行移動(), &正解.平行移動);
    let 回転の差 = 符号違いを同一視した最大の差(&得た配置.回転(), &正解.回転);
    let 倍率の差 = 最大の差(&得た配置.スケール(), &正解.倍率);
    if 移動の差 <= 許容差を求める(&得た配置.平行移動(), &正解.平行移動)
        && 回転の差 <= 許容差を求める(&得た配置.回転(), &正解.回転)
        && 倍率の差 <= 許容差を求める(&得た配置.スケール(), &正解.倍率)
    {
        return None;
    }
    Some(format!(
        "  {綴り}: 平行移動 得た{:?} 正解{:?} 差{移動の差:.6} / 回転 得た{:?} 正解{:?} 差{回転の差:.6} / 倍率 得た{:?} 正解{:?} 差{倍率の差:.6}",
        得た配置.平行移動(),
        正解.平行移動,
        得た配置.回転(),
        正解.回転,
        得た配置.スケール(),
        正解.倍率
    ))
}
