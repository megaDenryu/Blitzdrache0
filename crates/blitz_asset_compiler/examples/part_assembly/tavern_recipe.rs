//! 酒場宿屋の組み立て手順。どの部品のどの接合点へ何を繋ぐかを宣言として書く。
//!
//! **手順を宣言としてここへ書くのは、段2に規則がまだ無いためである。** 段3で規則を導入したとき、
//! 壁の面ごとに窓壁か扉壁かを種から選ぶ規則がこの手順を生む形になる。
//!
//! 面上の位置は部品の寸法から導出できない意匠の決定である。破風へ乗せるドーマーの横1.5メートルは、
//! Blender側の建築コードが`x_offset=1.5`と書いていた数値そのものである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「接合には2つの様式があり、検査すべきことが違う」

use blitz_assembly::{据えた部品の番号, 接合の指示, 接合点名, 接合面上の位置, 組み立て手順, 部品ID};
use blitz_math::メートル;

/// 煙突を手順へ入れないのは、種別と寸法の是正が本体のアセット置き場へまだ再収蔵されていないためである。
/// 再収蔵が済んだら壁面差込として1件足す。
pub fn 酒場宿屋の手順() -> Result<組み立て手順, String> {
    let 指示一覧 = vec![
        積む(0, "上面", "Mod_Tavern_F2_Jetty", "下面")?,
        積む(1, "上面", "Mod_Tavern_F3_Jetty", "下面")?,
        積む(2, "上面", "Mod_Tavern_Roof_Gable", "下面")?,
        付ける(2, "正面壁", "Mod_Tavern_Oriel_F2", "壁面差込口", 0.0)?,
        付ける(3, "破風正面壁", "Mod_Tavern_Dormer_Roof", "屋根面差込口", 1.5)?,
    ];
    Ok(組み立て手順::根と指示から生成する(
        識別子("Mod_Tavern_F1_Base")?,
        指示一覧,
    ))
}

fn 積む(親: usize, 親の接合点: &str, 子の部品: &str, 子の接合点: &str) -> Result<接合の指示, String> {
    指示を組む(親, 親の接合点, 子の部品, 子の接合点, 接合面上の位置::中心())
}

fn 付ける(親: usize, 親の接合点: &str, 子の部品: &str, 子の接合点: &str, 横: f32) -> Result<接合の指示, String> {
    let 位置 = 接合面上の位置::生成する(メートル::生成する(横), メートル::生成する(0.0)).map_err(|誤り| 誤り.to_string())?;
    指示を組む(親, 親の接合点, 子の部品, 子の接合点, 位置)
}

fn 指示を組む(
    親: usize, 親の接合点: &str, 子の部品: &str, 子の接合点: &str, 面上の位置: 接合面上の位置
) -> Result<接合の指示, String> {
    Ok(接合の指示 {
        親: 据えた部品の番号::番号から生成する(親),
        親の接合点: 名前(親の接合点)?,
        子の部品: 識別子(子の部品)?,
        子の接合点: 名前(子の接合点)?,
        面上の位置,
    })
}

fn 名前(綴り: &str) -> Result<接合点名, String> {
    接合点名::生成する(綴り).map_err(|誤り| 誤り.to_string())
}

fn 識別子(綴り: &str) -> Result<部品ID, String> {
    部品ID::生成する(綴り).map_err(|誤り| 誤り.to_string())
}
