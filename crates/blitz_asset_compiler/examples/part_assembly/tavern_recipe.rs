//! 酒場宿屋の組み立て手順。どの部品のどの接合点へ何を繋ぐかを宣言として書く。
//!
//! **手順を宣言としてここへ書くのは、段2に規則がまだ無いためである。** 段3で規則を導入したとき、
//! 壁の面ごとに窓壁か扉壁かを種から選ぶ規則がこの手順を生む形になる。
//!
//! 面上の位置も食い込ませる量も、部品の寸法から導出できない意匠の決定である。破風へ乗せるドーマーの横1.5メートルは、
//! Blender側の建築コードが`x_offset=1.5`と書いていた数値そのものである。食い込ませる量は、面をぴったり合わせると
//! 重複頂点の統合が非多様体を作るためにBlender側が入れている量であり、出窓が0.4メートル・ドーマーが0.7メートルである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「法線方向のずらしは配置の決定である」

use blitz_assembly::{
    据えた部品の番号, 接合の指示, 接合点名, 接合面上の位置, 法線方向のずらし, 組み立て手順, 部品ID
};
use blitz_math::メートル;

/// 煙突は差込面の種別と寸法が是正されて再収蔵されたため、土台の左側面壁への取付として1件入っている。
/// 横のずらしの-1.2メートルは、Blender側の建築が煙突を壁のどこへ寄せたかの意匠の決定である。
/// ドーマーが屋根面差込を名乗るのは、実体が屋根の傾斜面への取付であり、壁面と語を分けたためである。
pub fn 酒場宿屋の手順() -> Result<組み立て手順, String> {
    let 指示一覧 = vec![
        積む(0, "上面", "Mod_Tavern_F2_Jetty", "下面")?,
        積む(1, "上面", "Mod_Tavern_F3_Jetty", "下面")?,
        積む(2, "上面", "Mod_Tavern_Roof_Gable", "下面")?,
        付ける(2, "正面壁", "Mod_Tavern_Oriel_F2", "壁面差込口", 0.0, 0.4)?,
        付ける(3, "屋根前傾斜面", "Mod_Tavern_Dormer_Roof", "屋根面差込口", 1.5, 0.7)?,
        付ける(0, "左側面壁", "Mod_Tavern_Chimney", "壁面密着面", -1.2, 0.0)?,
    ];
    Ok(組み立て手順::根と指示から生成する(
        識別子("Mod_Tavern_F1_Base")?,
        指示一覧,
    ))
}

fn 積む(親: usize, 親の接合点: &str, 子の部品: &str, 子の接合点: &str) -> Result<接合の指示, String> {
    指示を組む(親, 親の接合点, 子の部品, 子の接合点, 接合面上の位置::中心(), 法線方向のずらし::寄せない())
}

/// 食い込ませる量を正の値で受けるのは、宣言の表がどれだけ埋めるかを負号なしで読めるようにするためである。
fn 付ける(
    親: usize, 親の接合点: &str, 子の部品: &str, 子の接合点: &str, 横: f32, 食い込ませる量: f32
) -> Result<接合の指示, String> {
    let 位置 = 接合面上の位置::生成する(メートル::生成する(横), メートル::生成する(0.0)).map_err(|誤り| 誤り.to_string())?;
    let 寄せ = 法線方向のずらし::食い込ませる量から生成する(メートル::生成する(食い込ませる量)).map_err(|誤り| 誤り.to_string())?;
    指示を組む(親, 親の接合点, 子の部品, 子の接合点, 位置, 寄せ)
}

fn 指示を組む(
    親: usize,
    親の接合点: &str,
    子の部品: &str,
    子の接合点: &str,
    面上の位置: 接合面上の位置,
    法線方向のずらし: 法線方向のずらし,
) -> Result<接合の指示, String> {
    Ok(接合の指示 {
        親: 据えた部品の番号::番号から生成する(親),
        親の接合点: 名前(親の接合点)?,
        子の部品: 識別子(子の部品)?,
        子の接合点: 名前(子の接合点)?,
        面上の位置,
        法線方向のずらし,
    })
}

fn 名前(綴り: &str) -> Result<接合点名, String> {
    接合点名::生成する(綴り).map_err(|誤り| 誤り.to_string())
}

fn 識別子(綴り: &str) -> Result<部品ID, String> {
    部品ID::生成する(綴り).map_err(|誤り| 誤り.to_string())
}
