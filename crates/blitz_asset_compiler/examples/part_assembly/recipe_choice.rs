//! 正解表が名乗る組み立ての識別子から、突き合わせる手順を選ぶ台帳。
//!
//! 手順を引数や旗で選ばせないのは、表と手順の取り違えが「全件が食い違う」という読み解きにくい結果になるためである。
//! 表が自分で何の組み立てかを名乗っており、その名前で引けば取り違えが起きない。
//!
//! 知らない識別子を黙って既定の手順で通さないのは、別の組み立ての表を渡した実行が、
//! 接合の計算の誤りに見える不一致を出すためである。

use blitz_assembly::組み立て手順;

use super::frame_recipe::{
    二段に積んだ骨格の手順, 壁をはめた一間四方の骨格の手順, 屋根を載せた一間四方の家の手順
};
use super::frame_recipe::{
    屋根を載せた二段の家の手順, 横に二ベイ継いだ骨格の手順, 煙突を付けた一間四方の家の手順
};
use super::tavern_recipe::酒場宿屋の手順;
use super::tree_recipe::標準の樫の木の手順;

const 酒場宿屋の識別子: &str = "Building_TavernInn";
const 標準の樫の木の識別子: &str = "Tree_Oak_Standard";
const 壁をはめた一間四方の骨格の識別子: &str = "Frame_Bay_Single_Walled";
const 二段に積んだ骨格の識別子: &str = "Frame_Bay_Two_Story";
const 横に二ベイ継いだ骨格の識別子: &str = "Frame_Bay_Row_Two";
const 屋根を載せた一間四方の家の識別子: &str = "Frame_Bay_House";
const 屋根を載せた二段の家の識別子: &str = "Frame_Two_Story_House";
const 煙突を付けた一間四方の家の識別子: &str = "Frame_Bay_House_Chimney";

const 持っている識別子一覧: [&str; 8] = [
    酒場宿屋の識別子,
    標準の樫の木の識別子,
    壁をはめた一間四方の骨格の識別子,
    二段に積んだ骨格の識別子,
    横に二ベイ継いだ骨格の識別子,
    屋根を載せた一間四方の家の識別子,
    屋根を載せた二段の家の識別子,
    煙突を付けた一間四方の家の識別子,
];

pub fn 正解表の識別子から手順を選ぶ(識別子: &str) -> Result<組み立て手順, String> {
    match 識別子 {
        酒場宿屋の識別子 => 酒場宿屋の手順(),
        標準の樫の木の識別子 => 標準の樫の木の手順(),
        壁をはめた一間四方の骨格の識別子 => 壁をはめた一間四方の骨格の手順(),
        二段に積んだ骨格の識別子 => 二段に積んだ骨格の手順(),
        横に二ベイ継いだ骨格の識別子 => 横に二ベイ継いだ骨格の手順(),
        屋根を載せた一間四方の家の識別子 => 屋根を載せた一間四方の家の手順(),
        屋根を載せた二段の家の識別子 => 屋根を載せた二段の家の手順(),
        煙突を付けた一間四方の家の識別子 => 煙突を付けた一間四方の家の手順(),
        他 => Err(format!(
            "この突き合わせ器が手順を持たない組み立てである: {他}(持っているのは{})",
            持っている識別子一覧.join("と")
        )),
    }
}
