//! 組み上げた部品が親と接していることの検査。**宙に浮いた部品を捉えるための項目である。**
//!
//! 貫入の不在を見ないのは、実データで部品が互いに食い込むことが正常だからである。2階の張り出しは1階の
//! 上面より下へ出て、出窓は壁の内側へ差し込む。差し込むことがまさに`壁面差込`という種別の意味である。
//! 接合面の矩形へ子の境界箱が収まることも見ない。出窓の屋根は壁面より外へ張り出しており、収まらないのが正常である。
//!
//! 残るのは「親と離れていないこと」である。接合点の宣言がメッシュの実物とずれていれば、組み上げた部品は
//! 親から離れた場所へ据わる。それはこの検査に出る。
//! 参照: `_doc/設計/部品カタログと接合点.md`「段2の完了条件」

use blitz_assembly::{組み立て手順, 群ローカルの箱};

use super::part_boxes::部品ごとの箱;

pub struct 接触の検査結果 {
    pub 接している件数: usize,
    pub 離れている行一覧: Vec<String>,
}

impl 接触の検査結果 {
    /// 手順の指示ごとに、子の箱が親の箱と接しているかを見る。根は親を持たないため対象外である。
    pub fn 手順にそって確かめる(手順: &組み立て手順, 箱一覧: &部品ごとの箱) -> Self {
        let mut 結果 = Self {
            接している件数: 0,
            離れている行一覧: Vec::new(),
        };
        for (添字, 指示) in 手順.指示一覧().iter().enumerate() {
            let 親の綴り = 箱一覧.番号の部品の綴り(指示.親.番号を返す());
            let 子の綴り = 指示.子の部品.綴り();
            let (Some(親の箱), Some(子の箱)) = (箱一覧.番号で写した箱を引く(指示.親.番号を返す()), 箱一覧.番号で写した箱を引く(添字 + 1))
            else {
                結果.離れている行一覧.push(format!("  指示[{添字}]: 箱を求められない"));
                continue;
            };
            結果.親と子の1組を確かめる(添字, &親の綴り, 子の綴り, &親の箱, &子の箱);
        }
        結果
    }

    fn 親と子の1組を確かめる(
        &mut self, 添字: usize, 親の綴り: &str, 子の綴り: &str, 親の箱: &群ローカルの箱, 子の箱: &群ローカルの箱
    ) {
        if 親の箱.相手と接するか(子の箱) {
            self.接している件数 += 1;
            return;
        }
        let 隙間 = 親の箱.相手との最大の隙間(子の箱);
        self.離れている行一覧.push(format!(
            "  指示[{添字}]: {子の綴り}が親の{親の綴り}から離れている(最大の隙間{隙間:.6}メートル)"
        ));
    }
}
