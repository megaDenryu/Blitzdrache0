//! 標準の樫の木の組み立て手順。どの部品のどの接合点へ何を繋ぐかを宣言として書く。
//!
//! **規則でなく手順を書くのは、この突き合わせが見るものが規則の選択でないからである。** ここで確かめるのは
//! 接合の計算がBlender側の配置と一致することであり、節ごとにどの生え口を種で引くかは別の関心事である。
//! 正解表は「節ごとに違う生え口を1つずつ使った標準の木」であるため、その組み立てをそのまま書く。
//!
//! 木の接合はどれも面の中心で向かい合わせ、法線方向へ寄せない。生え口が幹の表面に在り、Blender側が
//! 食い込みを持たないためである。家の手順が持つ横のずらしと食い込ませる量は、木には1件も現れない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「段6: 散布の針葉樹を部品で組んだ木へ差し替える」

use blitz_assembly::{
    据えた部品の番号, 接合の指示, 接合点名, 接合面上の位置, 法線方向のずらし, 組み立て手順, 部品ID
};

const 幹: &str = "Mod_Tree_Oak_Trunk_Segment";
const 枝: &str = "Mod_Tree_Oak_Branch_Large";
const 葉房: &str = "Mod_Tree_Oak_Foliage_Cluster";

/// 幹を3節積み、節ごとに違う生え口から枝を1本ずつ出し、その先へ葉房を付け、幹の頂へ冠の葉房を載せる。
/// 据えた番号は根の幹が0であり、指示を1つ積むごとに1つ増える。
pub fn 標準の樫の木の手順() -> Result<組み立て手順, String> {
    let 指示一覧 = vec![
        継ぐ(0, "幹頂部", 幹, "幹基部")?,
        継ぐ(1, "幹頂部", 幹, "幹基部")?,
        継ぐ(0, "生え口1", 枝, "枝の根元")?,
        継ぐ(3, "頂芽", 葉房, "葉房の根元")?,
        継ぐ(1, "生え口2", 枝, "枝の根元")?,
        継ぐ(5, "頂芽", 葉房, "葉房の根元")?,
        継ぐ(2, "生え口3", 枝, "枝の根元")?,
        継ぐ(7, "頂芽", 葉房, "葉房の根元")?,
        継ぐ(2, "幹頂部", 葉房, "幹基部")?,
    ];
    Ok(組み立て手順::根と指示から生成する(識別子(幹)?, 指示一覧))
}

fn 継ぐ(親: usize, 親の接合点: &str, 子の部品: &str, 子の接合点: &str) -> Result<接合の指示, String> {
    Ok(接合の指示 {
        親: 据えた部品の番号::番号から生成する(親),
        親の接合点: 名前(親の接合点)?,
        子の部品: 識別子(子の部品)?,
        子の接合点: 名前(子の接合点)?,
        面上の位置: 接合面上の位置::中心(),
        法線方向のずらし: 法線方向のずらし::寄せない(),
    })
}

fn 名前(綴り: &str) -> Result<接合点名, String> {
    接合点名::生成する(綴り).map_err(|誤り| 誤り.to_string())
}

fn 識別子(綴り: &str) -> Result<部品ID, String> {
    部品ID::生成する(綴り).map_err(|誤り| 誤り.to_string())
}
