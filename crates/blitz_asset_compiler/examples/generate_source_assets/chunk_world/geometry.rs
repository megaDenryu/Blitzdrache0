//! チャンク世界の共有バッファ。1チャンク分の板をチャンク局所座標の頂点として直列化する。
//! 区間の並び順(位置→法線→接線→UV→インデックス)と各区間のバイト長はgltf_jsonのbufferViewsへ手動で一致させている。
//! 注意: 頂点へ大域位置を焼かない。世界での配置は描画の基準原点(チャンク座標×一辺長)が担うため、
//! 焼くと平行移動が二重に掛かる(参照: `_doc/設計/地形とカメラ相対描画.md`「適用点: チャンク由来の描画の基準原点」)。

use super::{板の半辺, 板の局所中心};

/// 1チャンク分の区間長。位置48 + 法線48 + 接線64 + UV32 + インデックス12 の合計である。
pub(super) const チャンク当たりバイト長: usize = 204;

pub(super) fn 共有バッファバイト列を作る(チャンク数: usize) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(チャンク数 * チャンク当たりバイト長);
    for _ in 0..チャンク数 {
        バイト列.extend_from_slice(&一チャンク分を作る());
    }
    バイト列
}

/// XZ平面に法線+Yで置いた板を作る。UのプラスがワールドX、Vのプラスがワールド-Zに一致する構図のため、
/// 接線(dPos/dU)=(1,0,0)・w=+1(cross(法線,接線)=(0,0,-1)がdPos/dVと一致)が幾何学的に正しい値になる。
/// 全チャンクが同じ局所頂点を持つため、チャンクごとの差は描画の基準原点だけになる。
fn 一チャンク分を作る() -> Vec<u8> {
    let 最小 = 板の局所中心 - 板の半辺;
    let 最大 = 板の局所中心 + 板の半辺;
    let 位置一覧: [[f32; 3]; 4] = [[最小, 0.0, 最大], [最大, 0.0, 最大], [最大, 0.0, 最小], [最小, 0.0, 最小]];
    let 法線一覧: [[f32; 3]; 4] = [[0.0, 1.0, 0.0]; 4];
    let 接線一覧: [[f32; 4]; 4] = [[1.0, 0.0, 0.0, 1.0]; 4];
    let テクスチャ座標一覧: [[f32; 2]; 4] = [[0.0, 0.0], [1.0, 0.0], [1.0, 1.0], [0.0, 1.0]];
    let インデックス一覧: [u16; 6] = [0, 1, 2, 0, 2, 3];

    let mut バイト列 = Vec::with_capacity(チャンク当たりバイト長);
    小数を並べる(&mut バイト列, 位置一覧.iter().flatten());
    小数を並べる(&mut バイト列, 法線一覧.iter().flatten());
    小数を並べる(&mut バイト列, 接線一覧.iter().flatten());
    小数を並べる(&mut バイト列, テクスチャ座標一覧.iter().flatten());
    for インデックス in インデックス一覧 {
        バイト列.extend_from_slice(&インデックス.to_le_bytes());
    }
    バイト列
}

fn 小数を並べる<'成分>(バイト列: &mut Vec<u8>, 成分一覧: impl Iterator<Item = &'成分 f32>) {
    for 成分 in 成分一覧 {
        バイト列.extend_from_slice(&成分.to_le_bytes());
    }
}
