//! 植生の原型となる直方体の頂点バイト列。1本の柱を6面24頂点36インデックスで表す。
//! 区間の並び順(位置→法線→接線→UV→インデックス)と各区間のバイト長はgltf_jsonのbufferViewsへ手動で一致させている。
//! 直方体にするのは、個体ごとのY軸回転でどの向きを向いても画素判定で塊として見えるためである。板だと真横からほぼ消える。
//! 諸元を引数で受け取るのは、メッシュLOD列の段ごとに寸法の違う直方体を同じ並びで書き出すためである。
//! 段が違っても頂点数とインデックス数は変わらないため、直方体1つぶんのバイト長は諸元によらず一定である。

/// 1面ぶんの頂点数。6面で24頂点になる。
const 面の頂点数: usize = 4;

pub(super) const 位置区間長: usize = 24 * 12;
pub(super) const 法線区間長: usize = 24 * 12;
pub(super) const 接線区間長: usize = 24 * 16;
pub(super) const テクスチャ座標区間長: usize = 24 * 8;
pub(super) const インデックス区間長: usize = 36 * 2;

/// 直方体1つぶんのバイト長。2段目以降の区間はこの長さの倍数から始まる。
pub(super) const 直方体のバイト長: usize = 位置区間長 + 法線区間長 + 接線区間長 + テクスチャ座標区間長 + インデックス区間長;

/// メッシュLOD段1つぶんの直方体の寸法。水平の半辺と高さで決まり、底面は常にy=0にある。
#[derive(Clone, Copy)]
pub(super) struct 直方体諸元 {
    pub(super) 半辺: f32,
    pub(super) 高さ: f32,
}

struct 面 {
    法線: [f32; 3],
    接線: [f32; 4],
    位置一覧: [[f32; 3]; 面の頂点数],
}

pub(super) fn バッファバイト列を作る(諸元一覧: &[直方体諸元]) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(直方体のバイト長 * 諸元一覧.len());
    for 諸元 in 諸元一覧 {
        直方体を並べる(&mut バイト列, *諸元);
    }
    バイト列
}

fn 直方体を並べる(バイト列: &mut Vec<u8>, 諸元: 直方体諸元) {
    let 面一覧 = 面一覧を作る(諸元);
    小数を並べる(バイト列, 面一覧.iter().flat_map(|面| 面.位置一覧.iter().flatten().copied()));
    小数を並べる(バイト列, 面一覧.iter().flat_map(|面| 面.法線.iter().copied().cycle().take(12)));
    小数を並べる(バイト列, 面一覧.iter().flat_map(|面| 面.接線.iter().copied().cycle().take(16)));
    小数を並べる(バイト列, 面一覧.iter().flat_map(|_| [0.0, 0.0, 1.0, 0.0, 1.0, 1.0, 0.0, 1.0]));
    for 面番号 in 0..面一覧.len() {
        let 基点 = u16::try_from(面番号 * 面の頂点数).unwrap_or_else(|_| panic!("面の基点がu16に収まらない"));
        for 相対 in [0, 1, 2, 0, 2, 3] {
            バイト列.extend_from_slice(&(基点 + 相対).to_le_bytes());
        }
    }
}

/// 面の並びは+Z、-Z、+X、-X、+Y、-Yで固定する。頂点の並びはUVの[0,0]・[1,0]・[1,1]・[0,1]と対応する。
fn 面一覧を作る(諸元: 直方体諸元) -> [面; 6] {
    let 半辺 = 諸元.半辺;
    let 上 = 諸元.高さ;
    [
        面 {
            法線: [0.0, 0.0, 1.0],
            接線: [1.0, 0.0, 0.0, 1.0],
            位置一覧: [[-半辺, 0.0, 半辺], [半辺, 0.0, 半辺], [半辺, 上, 半辺], [-半辺, 上, 半辺]],
        },
        面 {
            法線: [0.0, 0.0, -1.0],
            接線: [-1.0, 0.0, 0.0, 1.0],
            位置一覧: [[半辺, 0.0, -半辺], [-半辺, 0.0, -半辺], [-半辺, 上, -半辺], [半辺, 上, -半辺]],
        },
        面 {
            法線: [1.0, 0.0, 0.0],
            接線: [0.0, 0.0, -1.0, 1.0],
            位置一覧: [[半辺, 0.0, 半辺], [半辺, 0.0, -半辺], [半辺, 上, -半辺], [半辺, 上, 半辺]],
        },
        面 {
            法線: [-1.0, 0.0, 0.0],
            接線: [0.0, 0.0, 1.0, 1.0],
            位置一覧: [[-半辺, 0.0, -半辺], [-半辺, 0.0, 半辺], [-半辺, 上, 半辺], [-半辺, 上, -半辺]],
        },
        面 {
            法線: [0.0, 1.0, 0.0],
            接線: [1.0, 0.0, 0.0, 1.0],
            位置一覧: [[-半辺, 上, 半辺], [半辺, 上, 半辺], [半辺, 上, -半辺], [-半辺, 上, -半辺]],
        },
        面 {
            法線: [0.0, -1.0, 0.0],
            接線: [1.0, 0.0, 0.0, 1.0],
            位置一覧: [[-半辺, 0.0, -半辺], [半辺, 0.0, -半辺], [半辺, 0.0, 半辺], [-半辺, 0.0, 半辺]],
        },
    ]
}

fn 小数を並べる(バイト列: &mut Vec<u8>, 成分一覧: impl Iterator<Item = f32>) {
    for 成分 in 成分一覧 {
        バイト列.extend_from_slice(&成分.to_le_bytes());
    }
}
