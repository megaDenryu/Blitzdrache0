//! 直方体の6面それぞれの向きと張り方、および1面を格子へ割った頂点の並び。
//! 受け取るのは直方体の諸元、返すのは面の一覧と、面1枚ぶんの位置列とテクスチャ座標列である。
//!
//! 面を角と2本の辺ベクトルで表すのは、格子の頂点を「角 + 辺 × 比率」の1つの式で置けるようにするためである。
//! 比率は両端を含む刻みであり、面に垂直な成分では辺ベクトルの成分が0であるから、角の値がそのまま残る。
//! これが「細分化した頂点が面の上に乗る」ことの根拠である。

use super::super::geometry::直方体諸元;

/// 面を割る位置の比率。両端を含む。刻みを2の冪にするのは、比率と辺の長さの積が丸めで面から浮かないためである。
pub(super) const 分割の比率: [f32; 5] = [0.0, 0.25, 0.5, 0.75, 1.0];

pub(super) const 面数: usize = 6;
pub(super) const 一辺の頂点数: usize = 分割の比率.len();
pub(super) const 面の頂点数: usize = 一辺の頂点数 * 一辺の頂点数;
pub(super) const 面の格子数: usize = (一辺の頂点数 - 1) * (一辺の頂点数 - 1);

pub(super) struct 面 {
    pub(super) 法線: [f32; 3],
    pub(super) 接線: [f32; 4],
    原点: [f32; 3],
    u方向: [f32; 3],
    v方向: [f32; 3],
}

impl 面 {
    /// 格子の頂点位置を、テクスチャ座標の第2成分の昇順・第1成分の昇順で並べたもの。
    pub(super) fn 位置一覧(&self) -> Vec<[f32; 3]> {
        let mut 一覧 = Vec::with_capacity(面の頂点数);
        for v比率 in 分割の比率 {
            for u比率 in 分割の比率 {
                一覧.push([0, 1, 2].map(|軸| self.原点[軸] + self.u方向[軸] * u比率 + self.v方向[軸] * v比率));
            }
        }
        一覧
    }
}

/// 格子の頂点のテクスチャ座標。並び順は位置と同じであり、面の向きに依らないためどの面でも同じ列である。
pub(super) fn テクスチャ座標一覧() -> Vec<[f32; 2]> {
    let mut 一覧 = Vec::with_capacity(面の頂点数);
    for v比率 in 分割の比率 {
        for u比率 in 分割の比率 {
            一覧.push([u比率, v比率]);
        }
    }
    一覧
}

/// 面の並びは+Z、-Z、+X、-X、+Y、-Yで固定する。原点と2本の辺は、粗い原型の面の角4つと同じ四角形を張る。
pub(super) fn 面一覧を作る(諸元: 直方体諸元) -> [面; 6] {
    let 半辺 = 諸元.半辺;
    let 幅 = 半辺 * 2.0;
    let 上 = 諸元.高さ;
    [
        面 {
            法線: [0.0, 0.0, 1.0],
            接線: [1.0, 0.0, 0.0, 1.0],
            原点: [-半辺, 0.0, 半辺],
            u方向: [幅, 0.0, 0.0],
            v方向: [0.0, 上, 0.0],
        },
        面 {
            法線: [0.0, 0.0, -1.0],
            接線: [-1.0, 0.0, 0.0, 1.0],
            原点: [半辺, 0.0, -半辺],
            u方向: [-幅, 0.0, 0.0],
            v方向: [0.0, 上, 0.0],
        },
        面 {
            法線: [1.0, 0.0, 0.0],
            接線: [0.0, 0.0, -1.0, 1.0],
            原点: [半辺, 0.0, 半辺],
            u方向: [0.0, 0.0, -幅],
            v方向: [0.0, 上, 0.0],
        },
        面 {
            法線: [-1.0, 0.0, 0.0],
            接線: [0.0, 0.0, 1.0, 1.0],
            原点: [-半辺, 0.0, -半辺],
            u方向: [0.0, 0.0, 幅],
            v方向: [0.0, 上, 0.0],
        },
        面 {
            法線: [0.0, 1.0, 0.0],
            接線: [1.0, 0.0, 0.0, 1.0],
            原点: [-半辺, 上, 半辺],
            u方向: [幅, 0.0, 0.0],
            v方向: [0.0, 0.0, -幅],
        },
        面 {
            法線: [0.0, -1.0, 0.0],
            接線: [1.0, 0.0, 0.0, 1.0],
            原点: [-半辺, 0.0, -半辺],
            u方向: [幅, 0.0, 0.0],
            v方向: [0.0, 0.0, 幅],
        },
    ]
}
