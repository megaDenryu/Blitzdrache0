//! 高さ地形の検証用世界の定義と、そのソースアセット一式の書き出し。板の世界とは別の目録を持つ独立した世界である。
//! 世界の広がり(5×5)・一辺長・格子の細かさという世界そのものの決め事をこのモジュールが持ち、高さの合成関数は子モジュールが持つ。
//! ソースはメッシュでなく高さ格子であり、メッシュ化はアセットコンパイラが行う。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「地形の表現」

mod height;

use std::path::Path;

use blitz_asset_compiler::{高さ格子を切り出す, 高さ格子を格納する, 高さ格子諸元};
use blitz_engine::チャンク座標;

use crate::directory_source::{目録ソースを作る, 目録項目};

/// 板の世界と同じ広がりにして、固定経路や先読み半径の設定をそのまま流用できるようにする。
const 座標最小: i32 = -2;
const 座標最大: i32 = 2;
const 一辺メートル: f32 = 100.0;

/// 1チャンクを64分割し、格子点を65×65にする。2の冪であるため、段を粗くするたびに1つおきの点が次の段の格子点へそのまま乗る。
const 辺分割数: u16 = 64;

/// 隣接チャンクと重ねる縁の幅。中央差分で法線を求めるのに前後1点あれば足りる。
const 重なり幅: u8 = 1;

const 目録ソースファイル名: &str = "chunk_directory.txt";

pub(crate) fn 書き出す(出力先ディレクトリ: &Path) -> Result<(), String> {
    let 諸元 = 高さ格子諸元::生成する(辺分割数, 重なり幅, 一辺メートル).map_err(|誤り| 誤り.to_string())?;
    let mut 項目一覧 = Vec::new();
    for z in 座標最小..=座標最大 {
        for x in 座標最小..=座標最大 {
            let 座標 = チャンク座標::生成する(x, z);
            let 格子 = 高さ格子を切り出す(諸元, 座標, height::大域高さを求める).map_err(|誤り| 誤り.to_string())?;
            let ファイル名 = 格子ファイル名を作る(座標);
            書き込む(&出力先ディレクトリ.join(&ファイル名), &高さ格子を格納する(&格子))?;
            項目一覧.push(目録項目 {
                座標,
                アセット識別子: 名前を作る(座標),
                ソース相対パス: ファイル名,
            });
        }
    }
    書き込む(
        &出力先ディレクトリ.join(目録ソースファイル名),
        目録ソースを作る(一辺メートル, &項目一覧).as_bytes(),
    )
}

fn 名前を作る(座標: チャンク座標) -> String {
    format!("terrain_x{}_z{}", 座標.x(), 座標.z())
}

fn 格子ファイル名を作る(座標: チャンク座標) -> String {
    format!("{}.heightgrid", 名前を作る(座標))
}

fn 書き込む(パス: &Path, バイト列: &[u8]) -> Result<(), String> {
    std::fs::write(パス, バイト列).map_err(|誤り| format!("{}: {誤り}", パス.display()))
}
