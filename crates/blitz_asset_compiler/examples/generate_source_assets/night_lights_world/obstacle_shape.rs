//! 夜の多光源の検収世界へ置く遮蔽物の直方体の形と、その形をglTFのバッファバイト列へ直列化する工程。
//! 受け取るのは直方体の寸法、返すのは.binの中身である。文書の側が宣言する区間のバイト長を定数で公開する。
//!
//! 局所原点を底面の中心へ置くのは、据える側が地表高さをそのまま平行移動の天頂成分に使うためである
//! (参照: `crates/blitz_asset_compiler/src/fixed_placement/scene.rs`)。
//! 面ごとに頂点を分けるのは、4つの側面と上面と底面が別々の法線を持ち、稜線を丸めないためである。
//! 区間の並び順(位置→法線→インデックス)と各区間のバイト長は`obstacle_gltf_json`のbufferViewsへこの定数で渡している。

/// 直方体1つの寸法。底面については半分の長さで持つ。局所原点が底面の中心にあり、半分の長さがそのまま隅の座標になるためである。
#[derive(Clone, Copy)]
pub(super) struct 遮蔽物の直方体の寸法 {
    pub(super) 東西の半幅メートル: f32,
    pub(super) 南北の半幅メートル: f32,
    pub(super) 高さメートル: f32,
}

/// 面の数。直方体は側面4つと上面と底面で6つの面を持つ。
const 面の数: usize = 6;
pub(super) const 頂点数: usize = 面の数 * 4;
pub(super) const 添字数: usize = 面の数 * 6;
pub(super) const 位置のバイト長: usize = 頂点数 * 12;
pub(super) const インデックスのバイト長: usize = 添字数 * 2;

/// 面1つを、外から見て反時計回りに並べた四隅と、その面の法線で表す。
struct 遮蔽物の面 {
    四隅: [[f32; 3]; 4],
    法線: [f32; 3],
}

fn 面一覧を作る(寸法: 遮蔽物の直方体の寸法) -> [遮蔽物の面; 面の数] {
    let (右, 左) = (寸法.東西の半幅メートル, -寸法.東西の半幅メートル);
    let (手前, 奥) = (寸法.南北の半幅メートル, -寸法.南北の半幅メートル);
    let (上, 下) = (寸法.高さメートル, 0.0);
    [
        遮蔽物の面 {
            四隅: [[左, 上, 手前], [右, 上, 手前], [右, 上, 奥], [左, 上, 奥]],
            法線: [0.0, 1.0, 0.0],
        },
        遮蔽物の面 {
            四隅: [[左, 下, 奥], [右, 下, 奥], [右, 下, 手前], [左, 下, 手前]],
            法線: [0.0, -1.0, 0.0],
        },
        遮蔽物の面 {
            四隅: [[左, 下, 手前], [右, 下, 手前], [右, 上, 手前], [左, 上, 手前]],
            法線: [0.0, 0.0, 1.0],
        },
        遮蔽物の面 {
            四隅: [[右, 下, 奥], [左, 下, 奥], [左, 上, 奥], [右, 上, 奥]],
            法線: [0.0, 0.0, -1.0],
        },
        遮蔽物の面 {
            四隅: [[右, 下, 手前], [右, 下, 奥], [右, 上, 奥], [右, 上, 手前]],
            法線: [1.0, 0.0, 0.0],
        },
        遮蔽物の面 {
            四隅: [[左, 下, 奥], [左, 下, 手前], [左, 上, 手前], [左, 上, 奥]],
            法線: [-1.0, 0.0, 0.0],
        },
    ]
}

pub(super) fn 遮蔽物のバッファバイト列を作る(寸法: 遮蔽物の直方体の寸法) -> Vec<u8> {
    let 面一覧 = 面一覧を作る(寸法);
    let mut バイト列 = Vec::with_capacity(位置のバイト長 * 2 + インデックスのバイト長);
    for 面 in &面一覧 {
        for 隅 in 面.四隅 {
            三成分を足す(&mut バイト列, &隅);
        }
    }
    for 面 in &面一覧 {
        for _ in 0..4 {
            三成分を足す(&mut バイト列, &面.法線);
        }
    }
    for 面番号 in 0..面の数 {
        let 起点 = u16::try_from(面番号 * 4).unwrap_or_else(|_| panic!("遮蔽物の頂点番号がu16に収まらない"));
        for 添字 in [起点, 起点 + 1, 起点 + 2, 起点, 起点 + 2, 起点 + 3] {
            バイト列.extend_from_slice(&添字.to_le_bytes());
        }
    }
    バイト列
}

fn 三成分を足す(バイト列: &mut Vec<u8>, 三成分: &[f32; 3]) {
    for 成分 in 三成分 {
        バイト列.extend_from_slice(&成分.to_le_bytes());
    }
}
