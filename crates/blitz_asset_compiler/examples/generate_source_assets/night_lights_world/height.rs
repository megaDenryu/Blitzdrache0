//! 夜の多光源の世界の地面の高さ。大域サンプル添字から高さメートルを返す純関数であり、チャンクの区切りを知らない。
//! 街灯が並ぶ内側の起伏と、外へ向かう下りの2つを足し合わせる。
//!
//! 起伏の振幅を約0.9メートルに取るのは、点光源が作る明るさの輪が起伏の斜面で歪む形を絵に出すためである。
//! 完全な平面にすると、輪が真円のまま並ぶだけになり、光が面の向きに応じて当たっていることを絵から読めない。
//! 逆に振幅を大きくすると、街灯の足元の起伏が光の届く範囲そのものを変えてしまい、光の数を振ったときの
//! 明るさの変化と起伏の変化を絵の上で分けられなくなる。
//!
//! 外へ向かって下るのは、有限の地面の縁とその垂直面を絵から消すためである。夜の空を背にした地面の縁は、
//! 空との境目に直線として出て、街灯の輪より目立つ。中心から36メートル先で下り始め、チャンクの端の50メートルで
//! 4メートル下がる二次曲線にすると、街灯の並び(中心から最大26.25メートル)は下りに触れない。
//!
//! 下りの距離を縦横のずれの大きいほう(チェビシェフ距離)で測るのは、下りの等高線をチャンクの境界と同じ正方形に
//! するためである。中心からの直線距離で測ると角のほうが遠くなり、境界の高さが辺と角で食い違う。
//!
//! 注意: 三角関数の丸めは処理系に依存しうる。生成物を共有するため、別の処理系で作り直すと末尾ビットが変わることがある。

/// 大域サンプル添字1つあたりの距離。一辺100メートルを64分割した値であり、`night_lights_world`の諸元と一致させる。
const 刻みメートル: f32 = 100.0 / 64.0;

/// 街灯の並びの中心。チャンクの大域原点はX最小・Z最小の角にあるため、一辺100メートルの半分だけ内側である。
const 中心メートル: f32 = 50.0;

/// 下りが始まる中心からの距離。街灯の並びはこの内側にあるため、街灯の接地は下りに触れない。
const 平らな内側の半径メートル: f32 = 36.0;

/// チャンクの端までの距離と、そこまでに下がる高さ。
const 端の距離メートル: f32 = 50.0;
const 落差メートル: f32 = 4.0;

pub(super) fn 大域高さを求める(添字x: i16, 添字z: i16) -> f32 {
    let x = 座標メートル(添字x);
    let z = 座標メートル(添字z);
    内側の起伏(x, z) + 外へ向かう下り(x, z)
}

fn 内側の起伏(x: f32, z: f32) -> f32 {
    0.6 * (x / 17.0).sin() * (z / 19.0).cos() + 0.3 * (x / 7.0 + 1.1).sin() * (z / 9.0 - 0.6).sin()
}

fn 外へ向かう下り(x: f32, z: f32) -> f32 {
    let 距離 = (x - 中心メートル).abs().max((z - 中心メートル).abs());
    let 下りの進み = ((距離 - 平らな内側の半径メートル) / (端の距離メートル - 平らな内側の半径メートル)).max(0.0);
    -落差メートル * 下りの進み * 下りの進み
}

fn 座標メートル(添字: i16) -> f32 {
    f32::from(添字) * 刻みメートル
}
