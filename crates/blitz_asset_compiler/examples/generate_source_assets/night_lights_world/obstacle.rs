//! 夜の多光源の検収世界へ置く遮蔽物2件のソースの書き出し。担当するのは、2件それぞれの形と色とファイル名を
//! 1箇所へ集めることと、その形をglTFの文書とバイナリへ書き出すことである。
//!
//! 2件の形を「細く高い角柱」と「幅広く低い壁」に分けるのは、影の形で灯を見分けるためである。影付きの灯2件が
//! 同じ立方体を読む誤配線は、遮蔽物の形が同じだと絵が正しく見えてしまう。長く細い影と短く広い影に分けておくと、
//! 添字を取り違えた瞬間に影の形が入れ替わり、領域の明るさで捉えられる。
//! 参照: `_doc/設計/クラスタ多光源と点光源の影.md`「第5段階(点光源の影)が足す検収」
//!
//! 注意: ファイル名は`crates/blitz_asset_compiler/examples/compile_assets/world/night_lights_declaration.rs`が
//! 宣言するソース相対パスと同じ綴りでなければならない。食い違うとカタログ未登録という遠い場所の失敗になる。

use std::path::Path;

use super::obstacle_gltf_json::遮蔽物のgltf文書を組み立てる;
use super::obstacle_shape::{遮蔽物のバッファバイト列を作る, 遮蔽物の直方体の寸法};

/// 遮蔽物1件の宣言。形と色とファイル名を1つにまとめて持つのは、3つを別の表に分けると1件を足すときに
/// 3箇所を揃えて触ることになるためである。
struct 遮蔽物の宣言 {
    文書ファイル名: &'static str,
    バイナリファイル名: &'static str,
    寸法: 遮蔽物の直方体の寸法,
    ベースカラー: [f32; 3],
}

/// 灯の高さは4.0メートルである。高さ3.0メートルの角柱は灯までの残り1.0メートルへ光を絞り、
/// 灯からの水平距離のおよそ4倍まで届く長い影を落とす。
const 細く高い角柱: 遮蔽物の宣言 = 遮蔽物の宣言 {
    文書ファイル名: "tall_pillar.gltf",
    バイナリファイル名: "tall_pillar.bin",
    寸法: 遮蔽物の直方体の寸法 {
        東西の半幅メートル: 0.35,
        南北の半幅メートル: 0.35,
        高さメートル: 3.0,
    },
    ベースカラー: [0.62, 0.60, 0.56],
};

/// 高さ1.2メートルの壁は灯までの残り2.8メートルへ光を絞り、灯からの水平距離のおよそ1.4倍までしか影が伸びない。
/// 東西に3.0メートルあるため、影は角柱と逆に短くて広い。
const 幅広く低い壁: 遮蔽物の宣言 = 遮蔽物の宣言 {
    文書ファイル名: "wide_wall.gltf",
    バイナリファイル名: "wide_wall.bin",
    寸法: 遮蔽物の直方体の寸法 {
        東西の半幅メートル: 1.5,
        南北の半幅メートル: 0.35,
        高さメートル: 1.2,
    },
    ベースカラー: [0.62, 0.60, 0.56],
};

pub(super) fn 遮蔽物2件を書き出す(出力先ディレクトリ: &Path) -> Result<(), String> {
    一件を書き出す(出力先ディレクトリ, &細く高い角柱)?;
    一件を書き出す(出力先ディレクトリ, &幅広く低い壁)
}

fn 一件を書き出す(出力先ディレクトリ: &Path, 宣言: &遮蔽物の宣言) -> Result<(), String> {
    super::書き込む(
        &出力先ディレクトリ.join(宣言.バイナリファイル名),
        &遮蔽物のバッファバイト列を作る(宣言.寸法),
    )?;
    super::書き込む(
        &出力先ディレクトリ.join(宣言.文書ファイル名),
        遮蔽物のgltf文書を組み立てる(宣言.バイナリファイル名, 宣言.寸法, 宣言.ベースカラー).as_bytes(),
    )
}
