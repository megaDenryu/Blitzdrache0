//! 起動引数から「何をどこへ書き出すか」を読む工程。受け取るのは引数の並び、返すのは書き出す対象の判別共用体である。
//!
//! 知らない引数を無視せず失敗にするのは、綴りを打ち間違えた実行が検証用の世界一式の書き直しへ黙って落ちるためである。
//! ソースルートを引数で受け取るのは、決定性の検収が同じ種から2つの別のルートへ書き出して突き合わせるためであり、
//! 大規模世界のソースをgitの管理外のルートへ置くためでもある。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

use std::path::PathBuf;

use blitz_asset_compiler::{ソースルート, マップ生成の乱数の種};

/// 種を導く選択肢の綴り。綴りは`xtask/src/gen_game_map.rs`にも同じものがある。
const 種の選択肢の綴り: &str = "--game-map-seed";

/// ソースルートを導く選択肢の綴り。綴りは`xtask/src/gen_game_map.rs`にも同じものがある。
const ソースルートの選択肢の綴り: &str = "--source-root";

/// ソースルートを指定しなかったときの行き先。リポジトリへ収めた検証用の世界の置き場である。
const 既定のソースルート: &str = "assets";

pub(crate) enum 書き出す対象 {
    検証用の世界一式,
    場所巡りの世界 {
        種: マップ生成の乱数の種,
        ソースルート: ソースルート,
    },
}

pub(crate) fn 引数一覧から書き出す対象を読む(引数一覧: &[String]) -> Result<書き出す対象, String> {
    if 引数一覧.is_empty() {
        return Ok(書き出す対象::検証用の世界一式);
    }
    let mut 読んだ種 = None;
    let mut ソースルートのパス = PathBuf::from(既定のソースルート);
    let mut 残りの引数 = 引数一覧;
    loop {
        let [綴り, 値, 続き @ ..] = 残りの引数 else {
            break;
        };
        if 綴り == 種の選択肢の綴り {
            読んだ種 = Some(種を解析する(値)?);
        } else if 綴り == ソースルートの選択肢の綴り {
            ソースルートのパス = PathBuf::from(値);
        } else {
            return Err(format!(
                "知らない引数である: {綴り}(選べるのは{種の選択肢の綴り} <数>と{ソースルートの選択肢の綴り} <パス>だけである)"
            ));
        }
        残りの引数 = 続き;
    }
    if !残りの引数.is_empty() {
        return Err(format!("{}に続く値が無い", 残りの引数.join(" ")));
    }
    let Some(種) = 読んだ種 else {
        return Err(format!("{種の選択肢の綴り}と種の値が要る"));
    };
    Ok(書き出す対象::場所巡りの世界 {
        種,
        ソースルート: ソースルート::生成する(ソースルートのパス),
    })
}

fn 種を解析する(値: &str) -> Result<マップ生成の乱数の種, String> {
    値.parse::<u32>()
        .map(マップ生成の乱数の種::生成する)
        .map_err(|誤り| format!("{種の選択肢の綴り}の値を32ビットの非負整数として読めない({値}): {誤り}"))
}
