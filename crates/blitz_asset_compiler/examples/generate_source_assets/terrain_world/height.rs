//! 検証用地形の高さ。大域サンプル添字から高さメートルを返す純関数であり、チャンクの区切りを知らない。
//! 隣接する2つのチャンクが共有する標本は同じ添字で引かれるため、この関数が返す値がそのまま境界の高さの一致になる。
//!
//! 注意: 三角関数の丸めは処理系に依存しうる。生成物をリポジトリへ収めて共有するため、別の処理系で作り直すと末尾ビットが変わることがある。
//! アセットコンパイラの決定性は入力である高さ格子に対して閉じており、この揺れには依存しない。

/// 大域サンプル添字1つあたりの距離。一辺100メートルを64分割した値であり、`terrain_world`の諸元と一致させる。
const 刻みメートル: f32 = 100.0 / 64.0;

/// 周期の違う3つの波を重ねる。最も長い波が世界全体(500メートル)にわたる起伏を作り、短い波がチャンク内の細かい凹凸を作る。
/// 振幅の合計は約9.5メートルであり、一辺100メートルのチャンクに対して斜めから見て起伏と分かる高さになる。
pub(super) fn 大域高さを求める(添字x: i16, 添字z: i16) -> f32 {
    let x = 座標メートル(添字x);
    let z = 座標メートル(添字z);
    6.0 * (x / 70.0).sin() * (z / 90.0).cos()
        + 2.5 * (x / 23.0 + 1.7).sin() * (z / 31.0 - 0.4).sin()
        + (x / 11.0 - 2.2).cos() * (z / 13.0 + 0.9).cos()
}

fn 座標メートル(添字: i16) -> f32 {
    f32::from(添字) * 刻みメートル
}
