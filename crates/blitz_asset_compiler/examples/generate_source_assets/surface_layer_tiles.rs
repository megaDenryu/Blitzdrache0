//! 地表層のタイル画像の生成。担当するのは、地表材質の4層それぞれに対応する純色のタイルを書き出すことである。
//!
//! 純色にするのは、層の重みが正しい向きと正しい混ざり方で絵に出ているかを、画素の値と重みの格子から
//! 直に突き合わせるためである。模様のあるタイルは、絵の食い違いが「模様のせいか重みのせいか」を分けられなくする。
//! 段Dの実タイルが届いたら、この置き場の中身を差し替えるだけで管はそのまま通る。

use std::path::Path;

/// タイル1枚の一辺の画素数。純色であるため大きさは絵に影響しないが、実タイルと同じ2の冪にして
/// 縮小段の生成の経路を実タイルと同じにする。
const 一辺の画素数: u32 = 256;

/// 材質名と、その材質の純色。エディターのマテリアル台帳の初期の材質名と同じ綴りである。
/// 4色を互いに離すのは、混色の期待値と実測の食い違いが画素の値の差として現れるようにするためである。
const 材質ごとの純色: [(&str, [u8; 4]); 4] = [
    ("grass_a", [60, 140, 60, 255]),
    ("dirt_a", [130, 90, 50, 255]),
    ("rock_a", [140, 140, 140, 255]),
    ("sand_a", [200, 180, 110, 255]),
];

pub(crate) fn 書き出す(出力先ディレクトリ: &Path) -> Result<(), String> {
    for (材質名, 純色) in 材質ごとの純色 {
        let パス = 出力先ディレクトリ.join(format!("{材質名}.png"));
        let 画像 = image::RgbaImage::from_pixel(一辺の画素数, 一辺の画素数, image::Rgba(純色));
        画像.save(&パス).map_err(|誤り| format!("{}: {誤り}", パス.display()))?;
    }
    Ok(())
}
