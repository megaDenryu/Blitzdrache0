//! 見本の集落の地面の高さ。大域サンプル添字から高さメートルを返す純関数であり、チャンクの区切りを知らない。
//!
//! 振幅の合計は約1.5メートルであり、地形の世界の約9.5メートルより緩い。集落は平地に開けた場所へ作られるものであり、
//! 起伏が大きいと柵の列と石垣の列が地面を突き抜けたり浮いたりして、絵の破れが小物の側の欠陥に見えるためである。
//! 緩い起伏を残すのは、完全な平面にすると地面が単色に塗られて、小物の影だけが陰影の手がかりになるためである。
//!
//! 注意: 三角関数の丸めは処理系に依存しうる。生成物をリポジトリへ収めて共有するため、別の処理系で作り直すと末尾ビットが変わることがある。

/// 大域サンプル添字1つあたりの距離。一辺100メートルを64分割した値であり、`village_world`の諸元と一致させる。
const 刻みメートル: f32 = 100.0 / 64.0;

pub(super) fn 大域高さを求める(添字x: i16, 添字z: i16) -> f32 {
    let x = 座標メートル(添字x);
    let z = 座標メートル(添字z);
    1.1 * (x / 46.0).sin() * (z / 52.0).cos() + 0.35 * (x / 17.0 + 0.9).sin() * (z / 21.0 - 0.5).sin()
}

fn 座標メートル(添字: i16) -> f32 {
    f32::from(添字) * 刻みメートル
}
