//! 材質境界の検収シーンの頂点データをglTFのバッファバイト列へ直列化する。
//! 中身は左右に並ぶ2枚の板であり、間に隙間を空けて境界が画素で読めるようにしてある。両方とも法線+Zの平面に置く。
//! 区間の並び順(位置→法線→接線→UV→インデックス)と各区間のバイト長は`multi_material_gltf_json`のbufferViewsへ手動で一致させている。

/// 板1枚の左右の端。左の板は負側、右の板は正側に置き、中央の隙間で2つの材質の境界が分かれる。
const 外側の端: f32 = 1.2;
const 内側の端: f32 = 0.1;
const 上下の端: f32 = 0.6;

/// 位置・法線・接線・UV・インデックスを連結した.binの中身を作る。
pub(super) fn バッファバイト列を作る() -> Vec<u8> {
    let 位置一覧 = 位置を並べる();
    let インデックス一覧: [u16; 12] = [0, 1, 2, 0, 2, 3, 4, 5, 6, 4, 6, 7];

    let mut バイト列 = Vec::with_capacity(408);
    for 位置 in 位置一覧 {
        for 成分 in 位置 {
            バイト列.extend_from_slice(&成分.to_le_bytes());
        }
    }
    for _ in 0..8 {
        for 成分 in [0.0f32, 0.0, 1.0] {
            バイト列.extend_from_slice(&成分.to_le_bytes());
        }
    }
    // UのプラスがワールドX、VのプラスがワールドYに一致する構図のため、接線(dPos/dU)=(1,0,0)・w=+1が幾何学的に正しい(判断25)。
    for _ in 0..8 {
        for 成分 in [1.0f32, 0.0, 0.0, 1.0] {
            バイト列.extend_from_slice(&成分.to_le_bytes());
        }
    }
    for _ in 0..2 {
        for 座標 in [[0.0f32, 0.0], [1.0, 0.0], [1.0, 1.0], [0.0, 1.0]] {
            for 成分 in 座標 {
                バイト列.extend_from_slice(&成分.to_le_bytes());
            }
        }
    }
    for インデックス in インデックス一覧 {
        バイト列.extend_from_slice(&インデックス.to_le_bytes());
    }
    バイト列
}

/// 左の板の4頂点に続いて右の板の4頂点を並べる。どちらも反時計回りで表が+Zを向く。
fn 位置を並べる() -> [[f32; 3]; 8] {
    [
        [-外側の端, -上下の端, 0.0],
        [-内側の端, -上下の端, 0.0],
        [-内側の端, 上下の端, 0.0],
        [-外側の端, 上下の端, 0.0],
        [内側の端, -上下の端, 0.0],
        [外側の端, -上下の端, 0.0],
        [外側の端, 上下の端, 0.0],
        [内側の端, 上下の端, 0.0],
    ]
}
