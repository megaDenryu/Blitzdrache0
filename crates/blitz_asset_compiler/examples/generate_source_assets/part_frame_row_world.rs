//! 部品で組んだ一間四方の骨格の並びの世界の定義と、そのソースアセットの書き出し。書き出すのは骨格を載せる地面だけであり、
//! 部品そのものは本体リポジトリの外にあるアセットリポジトリから来る
//! (宣言は`crates/blitz_asset_compiler/examples/compile_assets/world/part_frame_row_declaration.rs`)。
//!
//! 地面を起伏の無い平面にするのは、骨格の底面が1つの水平面に載るためである。起伏があると、2.4メートル四方の
//! ベイの一方の辺が地面へ埋まり、もう一方の辺の下に隙間が空く。この世界が見るのは描画発行数と個体数と絵の成立であり、
//! 接地の破れをそこへ混ぜない。
//!
//! 家の並びの地面と同じ形を別のディレクトリへ書き出すのは、目録が1つの座標へ1つの安定IDしか持てないためである。
//! 安定IDが違えば初期カメラと検収の入口が分かれ、ベイ1つを近くで写す構図をこの世界だけに与えられる。
//!
//! 10棟の世界と100棟の世界がこの1つの地面を共有する。件数は焼く側の宣言が持ち、地面は同じものでよい。

use std::path::Path;

use blitz_asset_compiler::{高さ格子を切り出す, 高さ格子を格納する, 高さ格子諸元};
use blitz_engine::チャンク座標;

use crate::directory_source::{目録ソースを作る, 目録項目};

/// 100棟は間隔10メートルの10列10行であり、一辺100メートルのチャンクの内側へ収まる。世界は原点チャンク1つだけを持つ。
const チャンクのX: i32 = 0;
const チャンクのZ: i32 = 0;
const 一辺メートル: f32 = 100.0;

/// 家の並びの地面と同じ細かさにして、段の作られ方と接地の求め方をそのまま流用できるようにする。
const 辺分割数: u16 = 64;

/// 隣接チャンクと重ねる縁の幅。中央差分で法線を求めるのに前後1点あれば足りる。
const 重なり幅: u8 = 1;

/// 一間四方の骨格の並びのシーンを指す安定ID。`prop_`で始めることが、書き換えもピクセル判定も持たない検収計画を選ばせる。
/// 参照: `crates/blitz_app/src/smoke/mod.rs`
const シーン名: &str = "prop_part_frame_row";

const 格子ファイル名: &str = "prop_part_frame_row.heightgrid";
const 目録ソースファイル名: &str = "chunk_directory.txt";

pub(crate) fn 書き出す(出力先ディレクトリ: &Path) -> Result<(), String> {
    let 諸元 = 高さ格子諸元::生成する(辺分割数, 重なり幅, 一辺メートル).map_err(|誤り| 誤り.to_string())?;
    let 座標 = チャンク座標::生成する(チャンクのX, チャンクのZ);
    let 格子 = 高さ格子を切り出す(諸元, 座標, 平らな地面の高さを求める).map_err(|誤り| 誤り.to_string())?;
    書き込む(&出力先ディレクトリ.join(格子ファイル名), &高さ格子を格納する(&格子))?;
    let 項目一覧 = vec![目録項目 {
        座標,
        アセット識別子: シーン名.to_string(),
        ソース相対パス: 格子ファイル名.to_string(),
    }];
    書き込む(&出力先ディレクトリ.join(目録ソースファイル名), 目録ソースを作る(&項目一覧).as_bytes())
}

/// どの大域サンプル添字でも高さは0である。
fn 平らな地面の高さを求める(_添字x: i16, _添字z: i16) -> f32 {
    0.0
}

fn 書き込む(パス: &Path, バイト列: &[u8]) -> Result<(), String> {
    std::fs::write(パス, バイト列).map_err(|誤り| format!("{}: {誤り}", パス.display()))
}
