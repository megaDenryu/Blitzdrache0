//! 目的地に立てる目印の柱の形と、その形をglTFのバッファバイト列へ直列化する工程。返すのは.binの中身と、
//! 文書の側が宣言する区間のバイト長である。
//!
//! 形を四角柱にするのは、目印が地面のどこに立っているかを遠くから読み取れればよく、それ以上の情報を絵で伝えないためである。
//! 局所原点を柱の底の中心へ置くのは、据える側が地表高さをそのまま平行移動に使えるようにするためである。
//! 面ごとに頂点を分けるのは、4つの側面と上面と底面が別々の法線を持ち、稜線を丸めないためである。
//! 区間の並び順(位置→法線→インデックス)と各区間のバイト長は`marker_gltf_json`のbufferViewsへこの定数で渡している。

/// 柱の底面の半幅。一辺1.2メートルの四角柱になる。
pub(super) const 半幅メートル: f32 = 0.6;
/// 柱の高さ。1.2メートルほどのキツネの背丈の4倍あり、少し離れた丘の上からでも地面の中に見つけられる。
pub(super) const 高さメートル: f32 = 5.0;

/// 面の数。四角柱は側面4つと上面と底面で6つの面を持つ。
const 面の数: usize = 6;
pub(super) const 頂点数: usize = 面の数 * 4;
pub(super) const 添字数: usize = 面の数 * 6;
pub(super) const 位置のバイト長: usize = 頂点数 * 12;
pub(super) const インデックスのバイト長: usize = 添字数 * 2;

/// 面1つを、外から見て反時計回りに並べた四隅と、その面の法線で表す。
struct 柱の面 {
    四隅: [[f32; 3]; 4],
    法線: [f32; 3],
}

fn 面一覧を作る() -> [柱の面; 面の数] {
    let (右, 左, 手前, 奥, 上, 下) = (半幅メートル, -半幅メートル, 半幅メートル, -半幅メートル, 高さメートル, 0.0);
    [
        柱の面 {
            四隅: [[左, 上, 手前], [右, 上, 手前], [右, 上, 奥], [左, 上, 奥]],
            法線: [0.0, 1.0, 0.0],
        },
        柱の面 {
            四隅: [[左, 下, 奥], [右, 下, 奥], [右, 下, 手前], [左, 下, 手前]],
            法線: [0.0, -1.0, 0.0],
        },
        柱の面 {
            四隅: [[左, 下, 手前], [右, 下, 手前], [右, 上, 手前], [左, 上, 手前]],
            法線: [0.0, 0.0, 1.0],
        },
        柱の面 {
            四隅: [[右, 下, 奥], [左, 下, 奥], [左, 上, 奥], [右, 上, 奥]],
            法線: [0.0, 0.0, -1.0],
        },
        柱の面 {
            四隅: [[右, 下, 手前], [右, 下, 奥], [右, 上, 奥], [右, 上, 手前]],
            法線: [1.0, 0.0, 0.0],
        },
        柱の面 {
            四隅: [[左, 下, 奥], [左, 下, 手前], [左, 上, 手前], [左, 上, 奥]],
            法線: [-1.0, 0.0, 0.0],
        },
    ]
}

pub(super) fn バッファバイト列を作る() -> Vec<u8> {
    let 面一覧 = 面一覧を作る();
    let mut バイト列 = Vec::with_capacity(位置のバイト長 * 2 + インデックスのバイト長);
    for 面 in &面一覧 {
        for 隅 in 面.四隅 {
            三成分を足す(&mut バイト列, &隅);
        }
    }
    for 面 in &面一覧 {
        for _ in 0..4 {
            三成分を足す(&mut バイト列, &面.法線);
        }
    }
    for 面番号 in 0..面の数 {
        let 起点 = u16::try_from(面番号 * 4).unwrap_or_else(|_| panic!("目印の柱の頂点番号がu16に収まらない"));
        for 添字 in [起点, 起点 + 1, 起点 + 2, 起点, 起点 + 2, 起点 + 3] {
            バイト列.extend_from_slice(&添字.to_le_bytes());
        }
    }
    バイト列
}

fn 三成分を足す(バイト列: &mut Vec<u8>, 三成分: &[f32; 3]) {
    for 成分 in 三成分 {
        バイト列.extend_from_slice(&成分.to_le_bytes());
    }
}
