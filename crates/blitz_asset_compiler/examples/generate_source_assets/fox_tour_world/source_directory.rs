//! 場所巡りの世界のソース一式の置き場。ライブラリの世界のソースディレクトリを包み、この世界だけが持つファイル名の綴りと、
//! 座標からアセット名とファイル名を導く規則を足す。
//!
//! 綴りを型の中へ閉じるのは、ファイル名の写しが呼び出し側へ散ると、書く側と読む側で食い違ったときに
//! 「ファイルが無い」という遠い場所の失敗になるためである。ディレクトリ名そのものはライブラリが持ち、
//! 実行時形式へ焼く側と同じ1つを読む。

use blitz_asset_compiler::{
    ソースルート, 世界のソースディレクトリ, 場所巡りの世界のディレクトリ名, 生成の出力ルート
};
use blitz_engine::チャンク座標;

use super::height_grid_file::高さ格子のファイル;

const 目印のバイナリファイル名: &str = "destination_marker.bin";
const 目印の文書ファイル名: &str = "destination_marker.gltf";

/// 生成に使った乱数の種を書き出すファイルの名前。読み手は`xtask/src/fox_tour_map_seed.rs`であり、綴りは向こうにも同じものがある。
const 種を書き出すファイル名: &str = "map_seed.txt";

#[repr(transparent)]
pub(crate) struct 場所巡りの世界のソースディレクトリ(世界のソースディレクトリ);

impl 場所巡りの世界のソースディレクトリ {
    pub(crate) fn ソースルートの下に作る(ソースルート: &ソースルート) -> Result<Self, String> {
        let ディレクトリ = ソースルート.世界のソースディレクトリ(場所巡りの世界のディレクトリ名).作ってから開く()?;
        Ok(Self(ディレクトリ))
    }

    /// チャンク1つを指す安定IDの綴り。目録へ載せる名前と高さ格子のファイル名がこの1つから導かれる。
    pub(crate) fn チャンクのアセット名(座標: チャンク座標) -> String {
        format!("fox_tour_x{}_z{}", 座標.x(), 座標.z())
    }

    /// 目録が書く、目録ソースの置き場からの相対のファイル名。
    pub(crate) fn 高さ格子の相対ファイル名(座標: チャンク座標) -> String {
        format!("{}.heightgrid", Self::チャンクのアセット名(座標))
    }

    pub(crate) fn 高さ格子のファイル(&self, 座標: チャンク座標) -> 高さ格子のファイル {
        高さ格子のファイル::パスから作る(self.0.直下のファイルのパス(&Self::高さ格子の相対ファイル名(座標)))
    }

    pub(crate) fn 目録ソースを書き出す(&self, 本文: &str) -> Result<(), String> {
        書き込む(&self.0.チャンク目録ソースのパス(), 本文.as_bytes())
    }

    pub(crate) fn 目印の柱を書き出す(&self, バッファのバイト列: &[u8], 文書の綴り: &str) -> Result<(), String> {
        書き込む(&self.0.直下のファイルのパス(目印のバイナリファイル名), バッファのバイト列)?;
        書き込む(&self.0.直下のファイルのパス(目印の文書ファイル名), 文書の綴り.as_bytes())
    }

    /// 目印の文書が自分の中で参照するバッファのファイル名。文書の綴りを組む側へ渡す。
    pub(crate) fn 目印のバイナリの参照名() -> &'static str {
        目印のバイナリファイル名
    }

    pub(crate) fn 生成に使った乱数の種を書き出す(&self, 種の綴り: &str) -> Result<(), String> {
        書き込む(&self.0.直下のファイルのパス(種を書き出すファイル名), 種の綴り.as_bytes())
    }

    /// 生成台帳の置き場としてのこの置き場。台帳の読み書きは生成の出力ルートの側が担う。
    pub(crate) fn 台帳の置き場(&self) -> &生成の出力ルート {
        self.0.台帳の置き場()
    }

    pub(crate) fn 表示の綴り(&self) -> std::path::Display<'_> {
        self.0.表示の綴り()
    }
}

/// この置き場がファイルへ書く唯一の口。生値のパスがここより外へ出ない。
fn 書き込む(パス: &std::path::Path, バイト列: &[u8]) -> Result<(), String> {
    std::fs::write(パス, バイト列).map_err(|誤り| format!("{}: {誤り}", パス.display()))
}
