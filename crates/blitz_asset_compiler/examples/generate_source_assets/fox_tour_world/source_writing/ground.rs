//! 地面のチャンク一式を書き出す工程。書き出しの型が持つ置き場・種・格子の諸元・生成台帳を使い、
//! 返すのは焼き直しの勘定と目録項目の一覧である。
//!
//! 台帳の記録と現物の内容ハッシュが揃っているチャンクは高さ格子を作り直さない。作り直さないチャンクにも目録項目は要るため、
//! 据え置いたチャンクもこの工程が目録へ載せる。
//!
//! チャンクごとの書き出しを並列にしてよいのは、1つのチャンクの高さが大域サンプル添字と種だけから決まり、
//! 他のチャンクの結果を1つも読まないためである。台帳への記録と目録の組み立ては、並列の結果が揃ってから
//! 座標の順で行うため、出力は実行のたびに同じになる。

use blitz_asset_compiler::{
    チャンクの焼き直し判定, 内容ハッシュ, 焼き直しの勘定, 高さ格子を切り出す, 高さ格子を格納する
};
use blitz_engine::チャンク座標;
use rayon::iter::{IntoParallelIterator, ParallelIterator};

use super::super::height;
use super::super::source_directory::場所巡りの世界のソースディレクトリ;
use super::場所巡りの世界のソース書き出し;
use crate::directory_source::目録項目;

pub(super) struct 地面の書き出しの結果 {
    pub(super) 勘定: 焼き直しの勘定,
    pub(super) 目録項目一覧: Vec<目録項目>,
}

struct チャンク1つの書き出しの結果 {
    座標: チャンク座標,
    焼き直しの判定: チャンクの焼き直し判定,
    書き上がりの内容ハッシュ: 内容ハッシュ,
}

impl 場所巡りの世界のソース書き出し {
    pub(super) fn 地面のチャンク一式を書き出す(&mut self) -> Result<地面の書き出しの結果, String> {
        let この書き出し = &*self;
        let 結果一覧 = self
            .世界の定義
            .覆う座標一覧()
            .into_par_iter()
            .map(|座標| この書き出し.チャンク1つを書き出す(座標))
            .collect::<Result<Vec<_>, String>>()?;
        let 勘定 = 焼き直しの勘定::判定の一覧から数える(結果一覧.iter().map(|結果| 結果.焼き直しの判定));
        let mut 目録項目一覧 = Vec::with_capacity(結果一覧.len());
        for 結果 in 結果一覧 {
            self.生成台帳.内容ハッシュを記録する(結果.座標, 結果.書き上がりの内容ハッシュ);
            目録項目一覧.push(目録項目 {
                座標: 結果.座標,
                アセット識別子: 場所巡りの世界のソースディレクトリ::チャンクのアセット名(結果.座標),
                ソース相対パス: 場所巡りの世界のソースディレクトリ::高さ格子の相対ファイル名(結果.座標),
            });
        }
        Ok(地面の書き出しの結果 { 勘定, 目録項目一覧 })
    }

    fn チャンク1つを書き出す(&self, 座標: チャンク座標) -> Result<チャンク1つの書き出しの結果, String> {
        let 高さ格子のファイル = self.ソースディレクトリ.高さ格子のファイル(座標);
        let 判定 = self.生成台帳.チャンクを焼き直すかを判定する(
            座標,
            高さ格子のファイル.内容ハッシュを求める()?,
            高さ格子のファイル.揃っているか(),
        );
        let 書き上がりの内容ハッシュ = match 判定 {
            チャンクの焼き直し判定::据え置く { 内容ハッシュ } => 内容ハッシュ,
            チャンクの焼き直し判定::焼き直す => {
                let 格子 = 高さ格子を切り出す(self.世界の定義.高さ格子の諸元(), 座標, |添字x, 添字z| {
                    height::大域高さを求める(self.種.値(), 添字x, 添字z)
                })
                .map_err(|誤り| 誤り.to_string())?;
                let バイト列 = 高さ格子を格納する(&格子);
                高さ格子のファイル.書き出す(&バイト列)?;
                内容ハッシュ::バイト列から求める(&バイト列)
            }
        };
        Ok(チャンク1つの書き出しの結果 {
            座標,
            焼き直しの判定: 判定,
            書き上がりの内容ハッシュ,
        })
    }
}
