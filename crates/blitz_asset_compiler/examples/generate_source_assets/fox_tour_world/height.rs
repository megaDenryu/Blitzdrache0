//! 場所巡りの世界の高さを、乱数の種と大域サンプル添字から決める純関数。チャンクの区切りを知らない。
//! 隣接する2つのチャンクが共有する標本は同じ添字で引かれるため、この関数が返す値がそのまま境界の高さの一致になる。
//!
//! 升目の幅の違う3つの格子雑音を重ねる。最も広い升目が世界全体にわたる丘と谷を作り、狭い升目が歩いていて分かる
//! 細かい凹凸を作る。振幅の合計は約9メートルであり、一辺100メートルのチャンクに対して斜めから見て起伏と分かる高さになる。

use super::lattice_noise::格子雑音の値;

/// 世界全体にわたる丘と谷を作る層。升目の幅96標本は150メートルにあたる。
const 丘の升目の幅: i16 = 96;
const 丘の振幅メートル: f32 = 6.0;

/// チャンク1つの中で高低が変わる層。升目の幅32標本は50メートルにあたる。
const 起伏の升目の幅: i16 = 32;
const 起伏の振幅メートル: f32 = 2.2;

/// 歩いていて分かる細かい凹凸の層。升目の幅11標本は約17メートルにあたる。
const 凹凸の升目の幅: i16 = 11;
const 凹凸の振幅メートル: f32 = 0.8;

/// 層ごとに種をずらす量。同じ種の3つの層が同じ角の値を引くと、3つの波が重なって同じ形の相似形になる。
const 起伏の層の種のずらし: u32 = 0x9e37_79b9;
const 凹凸の層の種のずらし: u32 = 0x85eb_ca6b;

pub(super) fn 大域高さを求める(種: u32, 添字x: i16, 添字z: i16) -> f32 {
    let 丘 = 格子雑音の値(種, 添字x, 添字z, 丘の升目の幅) * 丘の振幅メートル;
    let 起伏 = 格子雑音の値(種 ^ 起伏の層の種のずらし, 添字x, 添字z, 起伏の升目の幅) * 起伏の振幅メートル;
    let 凹凸 = 格子雑音の値(種 ^ 凹凸の層の種のずらし, 添字x, 添字z, 凹凸の升目の幅) * 凹凸の振幅メートル;
    丘 + 起伏 + 凹凸
}
