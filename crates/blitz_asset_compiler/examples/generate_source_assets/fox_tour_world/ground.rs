//! 種から地面のチャンク一式を書き出す工程。受け取るのは出力先と種と読み込んだ生成台帳、返すのは焼き直しの勘定と
//! 目録項目の一覧である。世界の広がりと格子の細かさは親モジュールが持ち、ここは1チャンクずつの書き出しだけを担う。
//!
//! 台帳の記録と現物の内容ハッシュが揃っているチャンクは高さ格子を作り直さない。作り直さないチャンクにも目録項目は要るため、
//! 据え置いたチャンクもこの工程が目録へ載せる。
//!
//! チャンクごとの書き出しを並列にしてよいのは、1つのチャンクの高さが大域サンプル添字と種だけから決まり、
//! 他のチャンクの結果を1つも読まないためである。台帳への記録と目録の組み立ては、並列の結果が揃ってから
//! 座標の順で行うため、出力は実行のたびに同じになる。

use std::path::Path;

use blitz_asset_compiler::{
    チャンクの焼き直し判定, マップ生成の乱数の種, 内容ハッシュ, 焼き直しの勘定, 生成台帳, 高さ格子を切り出す, 高さ格子を格納する, 高さ格子諸元,
};
use blitz_engine::チャンク座標;
use rayon::iter::{IntoParallelIterator, ParallelIterator};

use super::height;
use crate::directory_source::目録項目;

pub(super) struct 地面の書き出しの結果 {
    pub(super) 勘定: 焼き直しの勘定,
    pub(super) 目録項目一覧: Vec<目録項目>,
}

struct チャンク1つの書き出しの結果 {
    座標: チャンク座標,
    格子ファイル名: String,
    焼き直しの判定: チャンクの焼き直し判定,
    書き上がりの内容ハッシュ: 内容ハッシュ,
}

pub(super) fn 種から地面のチャンク一式を書き出す(
    出力先ディレクトリ: &Path,
    種: マップ生成の乱数の種,
    台帳: &mut 生成台帳,
) -> Result<地面の書き出しの結果, String> {
    let 諸元 = 高さ格子諸元::生成する(super::辺分割数, super::重なり幅, super::一辺メートル).map_err(|誤り| 誤り.to_string())?;
    let 読み取り用の台帳: &生成台帳 = 台帳;
    let 結果一覧 = super::世界が覆う座標一覧()
        .into_par_iter()
        .map(|座標| チャンク1つを書き出す(出力先ディレクトリ, 種, 諸元, 読み取り用の台帳, 座標))
        .collect::<Result<Vec<_>, String>>()?;
    let 勘定 = 焼き直しの勘定::判定の一覧から数える(結果一覧.iter().map(|結果| 結果.焼き直しの判定));
    let mut 目録項目一覧 = Vec::with_capacity(結果一覧.len());
    for 結果 in 結果一覧 {
        台帳.内容ハッシュを記録する(結果.座標, 結果.書き上がりの内容ハッシュ);
        目録項目一覧.push(目録項目 {
            座標: 結果.座標,
            アセット識別子: super::チャンクの名前を作る(結果.座標),
            ソース相対パス: 結果.格子ファイル名,
        });
    }
    Ok(地面の書き出しの結果 { 勘定, 目録項目一覧 })
}

fn チャンク1つを書き出す(
    出力先ディレクトリ: &Path,
    種: マップ生成の乱数の種,
    諸元: 高さ格子諸元,
    台帳: &生成台帳,
    座標: チャンク座標,
) -> Result<チャンク1つの書き出しの結果, String> {
    let 格子ファイル名 = super::格子ファイル名を作る(座標);
    let 格子のパス = 出力先ディレクトリ.join(&格子ファイル名);
    let 今の内容ハッシュ = 内容ハッシュ::ファイルがあれば中身から求める(&格子のパス).map_err(|誤り| 誤り.to_string())?;
    let 判定 = 台帳.チャンクを焼き直すかを判定する(座標, 今の内容ハッシュ, &格子のパス);
    let 書き上がりの内容ハッシュ = match 判定 {
        チャンクの焼き直し判定::据え置く { 内容ハッシュ } => 内容ハッシュ,
        チャンクの焼き直し判定::焼き直す => {
            let 格子 =
                高さ格子を切り出す(諸元, 座標, |添字x, 添字z| height::大域高さを求める(種.値(), 添字x, 添字z)).map_err(|誤り| 誤り.to_string())?;
            let バイト列 = 高さ格子を格納する(&格子);
            super::書き込む(&格子のパス, &バイト列)?;
            内容ハッシュ::バイト列から求める(&バイト列)
        }
    };
    Ok(チャンク1つの書き出しの結果 {
        座標,
        格子ファイル名,
        焼き直しの判定: 判定,
        書き上がりの内容ハッシュ,
    })
}
