//! 生成に使った乱数の種をファイルへ書き出す工程。担当するのは書き出し先のファイル名と中身の綴りだけであり、
//! 種から高さをどう作るかも、書いた種を誰がどう見せるかもここは決めない。
//!
//! 種を世界のソースアセットと並べて書くのは、`cargo xtask game-fox-tour`が検収の種でこのディレクトリを
//! 作り直すため、別の種で作ったマップが黙って入れ替わりうるからである。読み手は`xtask/src/fox_tour_map_seed.rs`であり、
//! ファイル名の綴りは向こうにも同じものがある。綴りが食い違い、かつ古い綴りのファイルが残っていなければ、向こうが「種が分からない」を報告する(古いファイルが残っていると古い種を表示し続ける。生成は出力ディレクトリを掃除しないためである)。
//!
//! 中身を種の10進表記1行に限るのは、同じ種からの2度の生成がバイト一致することを`cargo xtask game-fox-tour`の
//! 決定性の検査が突き合わせており、時刻のような実行ごとに動く値を混ぜるとその検査が破れるためである。

use std::path::Path;

use crate::map_seed::マップ生成の乱数の種;

/// 生成に使った種を書き出すファイルの名前。
const 種を書き出すファイルの名前: &str = "map_seed.txt";

pub(super) fn マップの生成に使った乱数の種をファイルへ書き出す(
    出力先ディレクトリ: &Path,
    種: マップ生成の乱数の種,
) -> Result<(), String> {
    let パス = 出力先ディレクトリ.join(種を書き出すファイルの名前);
    super::書き込む(&パス, format!("{}\n", 種.値()).as_bytes())
}
