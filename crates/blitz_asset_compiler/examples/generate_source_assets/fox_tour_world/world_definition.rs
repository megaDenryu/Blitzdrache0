//! 場所巡りの世界の定義: この世界の決め事一式を1つの値として持つ型。広がり・チャンクの一辺長・格子の細かさ・
//! 隣接と重ねる縁の幅は互いに独立でないため、平坦な定数の列でなく1つの型に束ね、生成するで相互の制約を確かめる。
//!
//! 世界を3×3に留めるのは、1本目の遊びが3つの目的地を巡って終わる短いものであり、300メートル四方あれば
//! 目的地の間を歩く距離が取れるためである。大規模化は同じ器のまま広がりの値を増やして行う。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断7: 地図の正本を持ち、生成は2系統に分ける」

use blitz_asset_compiler::高さ格子諸元;
use blitz_engine::チャンク座標;

/// 世界が覆うチャンク座標の範囲。原点チャンクを中心に東西南北へ1つずつ広げた3×3である。
const 座標最小: i32 = -1;
const 座標最大: i32 = 1;
const 一辺メートル: f32 = 100.0;

/// 地形の世界と同じ細かさにして、段の作られ方と接地の求め方をそのまま流用できるようにする。
const 辺分割数: u16 = 64;

/// 隣接チャンクと重ねる縁の幅。中央差分で法線を求めるのに前後1点あれば足りる。
const 重なり幅: u8 = 1;

pub(super) struct 場所巡りの世界の定義 {
    座標最小: i32,
    座標最大: i32,
    高さ格子の諸元: 高さ格子諸元,
}

impl 場所巡りの世界の定義 {
    /// 決め事の相互の制約を確かめて作る。範囲が逆さまでないことをここで見るのは、逆さまだと世界が1チャンクも
    /// 覆わない生成が黙って成功するためである。格子の細かさと重なり幅と一辺長の制約は高さ格子の諸元が持つ。
    pub(super) fn 生成する() -> Result<Self, String> {
        if 座標最小 > 座標最大 {
            return Err(format!("世界の広がりが逆さまである(最小{座標最小}、最大{座標最大})"));
        }
        Ok(Self {
            座標最小,
            座標最大,
            高さ格子の諸元: 高さ格子諸元::生成する(辺分割数, 重なり幅, 一辺メートル).map_err(|誤り| 誤り.to_string())?,
        })
    }

    pub(super) fn 高さ格子の諸元(&self) -> 高さ格子諸元 {
        self.高さ格子の諸元
    }

    pub(super) fn 覆う座標一覧(&self) -> Vec<チャンク座標> {
        let 一辺のチャンク数 = usize::try_from(self.座標最大 - self.座標最小 + 1).unwrap_or_default();
        let mut 座標一覧 = Vec::with_capacity(一辺のチャンク数 * 一辺のチャンク数);
        for z in self.座標最小..=self.座標最大 {
            for x in self.座標最小..=self.座標最大 {
                座標一覧.push(チャンク座標::生成する(x, z));
            }
        }
        座標一覧
    }
}
