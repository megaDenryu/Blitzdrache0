//! 場所巡りの世界のソース書き出し: 1回の書き出しが持ち回る状態(置き場・種・世界の定義・生成台帳)を所有する型。
//! 書き出しの操作はこの型のメソッドであり、生成台帳を引数で受け渡す自由関数の連鎖にしない。
//!
//! 台帳を所有させるのは、台帳が「読み込む・照会する・記録する・確定する」の4つを1回の書き出しの間ずっと持ち回る
//! 状態だからである。引数で渡し歩くと、どの工程がどの段階の台帳を触れるかが署名からは分からなくなる。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

mod ground;

use blitz_asset_compiler::{
    ソースルート, マップ生成の乱数の種, 世界の広がり, 場所巡りの世界のソースディレクトリ, 焼き直しの勘定, 生成台帳, 生成台帳の見出し, 種の由来,
};

use super::world_definition::場所巡りの世界の定義;
use super::{marker_geometry, marker_gltf_json};
use crate::directory_source::目録ソースを作る;

pub(crate) struct 場所巡りの世界のソース書き出し {
    ソースディレクトリ: 場所巡りの世界のソースディレクトリ,
    種: マップ生成の乱数の種,
    世界の定義: 場所巡りの世界の定義,
    生成台帳: 生成台帳,
}

impl 場所巡りの世界のソース書き出し {
    pub(crate) fn 始める(
        ソースルート: &ソースルート, 種: マップ生成の乱数の種, 広がり: 世界の広がり
    ) -> Result<Self, String> {
        let ソースディレクトリ = 場所巡りの世界のソースディレクトリ::ソースルートの下に作る(ソースルート).map_err(|誤り| 誤り.to_string())?;
        let ディレクトリ名 = 場所巡りの世界のソースディレクトリ::ディレクトリ名().map_err(|誤り| 誤り.to_string())?;
        let 焼き方の指定 = 広がり.焼き方の指定を組み立てる(ディレクトリ名);
        let 見出し = 生成台帳の見出し::実行中の生成器から作る(種の由来::種から焼いた(種), &焼き方の指定).map_err(|誤り| 誤り.to_string())?;
        let 読み込み = 生成台帳::出力ルートから読み込む(ソースディレクトリ.台帳の置き場(), 見出し);
        if 読み込み.種または生成器の版が変わったか() {
            ソースディレクトリ.生成物一式を削除する().map_err(|誤り| 誤り.to_string())?;
        }
        let 生成台帳 = 読み込み.台帳を受け取る();
        Ok(Self {
            ソースディレクトリ,
            種,
            世界の定義: 場所巡りの世界の定義::生成する(広がり)?,
            生成台帳,
        })
    }

    /// ソース一式を書き出し、最後に台帳を確定する。返すのは焼き直しの勘定である。
    pub(crate) fn ソース一式を書き出して台帳を確定する(mut self) -> Result<焼き直しの勘定, String> {
        let 地面 = self.地面のチャンク一式を書き出す()?;
        self.ソースディレクトリ
            .目録ソースを書き出す(&目録ソースを作る(
                self.世界の定義.高さ格子の諸元().一辺メートル(),
                &地面.目録項目一覧,
            ))
            .map_err(|誤り| 誤り.to_string())?;
        self.目印の柱を書き出す()?;
        self.ソースディレクトリ
            .生成に使った乱数の種を書き出す(self.種)
            .map_err(|誤り| 誤り.to_string())?;
        self.ソースディレクトリ
            .現行対象外を削除する(&self.世界の定義.覆う座標一覧())
            .map_err(|誤り| 誤り.to_string())?;
        // 注意: 生成台帳は書き出す一式の最後に確定させる。ここより前で確定させると、目録ソースか目印の書き出しに失敗した
        // 実行が「新しい台帳と揃っていないソース一式」を残し、次の実行がチャンクを据え置いて欠けたまま先へ進む。
        self.生成台帳
            .出力ルートへ書き出す(self.ソースディレクトリ.台帳の置き場())
            .map_err(|誤り| 誤り.to_string())?;
        Ok(地面.勘定)
    }

    pub(crate) fn 表示の綴り(&self) -> std::path::Display<'_> {
        self.ソースディレクトリ.表示の綴り()
    }

    fn 目印の柱を書き出す(&self) -> Result<(), String> {
        let 文書 = marker_gltf_json::文書(場所巡りの世界のソースディレクトリ::目印のバイナリの参照名());
        self.ソースディレクトリ
            .目印の柱を書き出す(&marker_geometry::バッファバイト列を作る(), &文書)
            .map_err(|誤り| 誤り.to_string())
    }
}
