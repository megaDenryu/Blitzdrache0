//! 庭の丘の裾から水平に広がる遠景地面の生成。受け取るものは無く、返すのは1メッシュ1プリミティブのglTF文書とそのバイト列である。
//!
//! この板を置くのは、庭の丘が作る地平と天文学的な水平線の間へ空パスが暗い色を描くためである。帯の角度の幅は
//! 視点の高さを地平までの距離で割った値であり、地平を遠ざけるほど狭くなる。視点は庭の地面から約2.6メートル上にあるため、
//! 板をカメラの遠クリップ距離(10000メートル)より外まで広げると、残る帯は0.1度に満たない幅へ落ちる。
//! 板の外周そのものは遠クリップに切られて画面へ出ないため、この板の広さは「遠クリップより外まで届くこと」だけを満たせばよい。
//!
//! 板の高さを丘の下り終わりと同じにするのは、庭との間に段差を作らないためである。庭の起伏の項がチャンクの端でも
//! 最大0.8メートル残るため接続は厳密でないが、その位置は丘の尾根の裏側にあり視線が届かない。
//!
//! ベースカラーを庭の地面と別の値にするのは、検収の領域マスクが1色の一致で地面を選ぶためである。同じ色にすると
//! 遠景地面まで庭の地面として数えられ、破綻防止帯の割合が庭の性質を表さなくなる。

use super::height::落差メートル;

/// 板の半辺。カメラの遠クリップ距離10000メートルより外まで届き、どの向きでも遠クリップのほうが先に板を切る。
const 半辺メートル: f32 = 12000.0;

/// 遠景地面のベースカラー。庭の地面(0.14, 0.16, 0.10)よりわずかに明るくしてあり、sRGBへ符号化した3バイトが3成分とも違う値になる。
const ベースカラー: [f32; 3] = [0.155, 0.175, 0.115];
const 粗さ: f32 = 0.95;

const 頂点数: usize = 4;
const 位置のバイト長: usize = 頂点数 * 12;
const 法線のバイト長: usize = 位置のバイト長;
const インデックスのバイト長: usize = 6 * 2;

pub(super) fn バッファバイト列を作る() -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(位置のバイト長 + 法線のバイト長 + インデックスのバイト長);
    for 位置 in 四隅() {
        書き込む(&mut バイト列, 位置);
    }
    for _ in 0..頂点数 {
        書き込む(&mut バイト列, [0.0, 1.0, 0.0]);
    }
    for 添字 in [0u16, 1, 2, 0, 2, 3] {
        バイト列.extend_from_slice(&添字.to_le_bytes());
    }
    バイト列
}

/// 上から見て反時計回りに並ぶ4隅。この順で(辺1)×(辺2)が天頂を向く。
fn 四隅() -> [[f32; 3]; 頂点数] {
    let (右, 左, 手前, 奥, 高さ) = (半辺メートル, -半辺メートル, 半辺メートル, -半辺メートル, -落差メートル);
    [[左, 高さ, 手前], [右, 高さ, 手前], [右, 高さ, 奥], [左, 高さ, 奥]]
}

fn 書き込む(バイト列: &mut Vec<u8>, 値: [f32; 3]) {
    for 成分 in 値 {
        バイト列.extend_from_slice(&成分.to_le_bytes());
    }
}

pub(super) fn 文書(バイナリファイル名: &str) -> String {
    let 法線の開始 = 位置のバイト長;
    let インデックスの開始 = 法線の開始 + 法線のバイト長;
    let 全長 = インデックスの開始 + インデックスのバイト長;
    format!(
        r#"{{
  "asset": {{ "version": "2.0" }},
  "buffers": [ {{ "uri": "{バイナリファイル名}", "byteLength": {全長} }} ],
  "bufferViews": [
    {{ "buffer": 0, "byteOffset": 0, "byteLength": {位置のバイト長}, "target": 34962 }},
    {{ "buffer": 0, "byteOffset": {法線の開始}, "byteLength": {法線のバイト長}, "target": 34962 }},
    {{ "buffer": 0, "byteOffset": {インデックスの開始}, "byteLength": {インデックスのバイト長}, "target": 34963 }}
  ],
  "accessors": [
    {{ "bufferView": 0, "componentType": 5126, "count": {頂点数}, "type": "VEC3", "min": [{左}, {高さ}, {左}], "max": [{右}, {高さ}, {右}] }},
    {{ "bufferView": 1, "componentType": 5126, "count": {頂点数}, "type": "VEC3" }},
    {{ "bufferView": 2, "componentType": 5123, "count": 6, "type": "SCALAR" }}
  ],
  "materials": [
    {{ "pbrMetallicRoughness": {{ "baseColorFactor": [{赤}, {緑}, {青}, 1.0], "metallicFactor": 0.0, "roughnessFactor": {粗さ} }} }}
  ],
  "meshes": [ {{ "name": "遠景地面", "primitives": [
    {{ "attributes": {{ "POSITION": 0, "NORMAL": 1 }}, "indices": 2, "material": 0 }}
  ] }} ],
  "nodes": [ {{ "mesh": 0 }} ],
  "scenes": [ {{ "nodes": [0] }} ],
  "scene": 0
}}
"#,
        左 = -半辺メートル,
        右 = 半辺メートル,
        高さ = -落差メートル,
        赤 = ベースカラー[0],
        緑 = ベースカラー[1],
        青 = ベースカラー[2],
    )
}
