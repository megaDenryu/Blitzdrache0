//! 目視見本の世界の地面の高さ。大域サンプル添字から高さメートルを返す純関数であり、チャンクの区切りを知らない。
//! 庭の起伏と、庭から外へ向かう下りの2つを足し合わせる。
//!
//! 庭の起伏の振幅は約0.8メートルであり、見本の集落の約1.5メートルよりさらに緩い。この世界の主役は材質見本の球であり、
//! 起伏が大きいと球の映り込みへ地面が大きく入って粗さの比較が難しくなるためである。
//! 完全な平面にしないのは、平面だと地面が単色に塗られて方向光の当たり方の違いが読み取れなくなるためである。
//!
//! 庭から外へ向かって下るのは、有限の地面の縁とその垂直面を絵から消すためである。地面が丘の頂として外へ落ちると、
//! 手前の斜面が視線を遮り、縁より先が見えなくなる。中心から40メートル先で下り始めチャンクの端の50メートルで5メートル下がる
//! 二次曲線にすると、視点(庭の地面から約2.6メートル上・中心から約11.8メートル手前)から見て、地平は中心から40メートルの尾根に来て
//! 端の縁はその4.1度ぶん下へ隠れる。下り始めをできるだけ外側に取るのは、地平が遠いほど視点の高さぶんの見下ろし角が小さくなり、
//! 地平と天文学的な水平線の間に残る隙間が狭くなるためである。
//!
//! 逆に外周を隆起させて縁を隠す形は採れない。夜明けと夕方は太陽高度がちょうど0であり、視点の高さを超える外周は
//! 水平に届く方向光を庭ごと影へ入れてしまう。この2つの時刻の絵は方向光が小物の側面を照らすことで成り立っているため、
//! 隙間を完全に閉じることと引き換えにできない。
//!
//! 下りの距離を縦横のずれの大きいほう(チェビシェフ距離)で測るのは、下りの等高線をチャンクの境界と同じ正方形にするためである。
//! 中心からの直線距離で測ると角のほうが遠くなり、境界の高さが辺と角で食い違って縁の隠れ方が向きによって変わる。
//!
//! 注意: 三角関数の丸めは処理系に依存しうる。生成物をリポジトリへ収めて共有するため、別の処理系で作り直すと末尾ビットが変わることがある。

/// 大域サンプル添字1つあたりの距離。一辺100メートルを64分割した値であり、`terrain_visual_world`の諸元と一致させる。
const 刻みメートル: f32 = 100.0 / 64.0;

/// 庭の中心。チャンクの大域原点はX最小・Z最小の角にあるため、一辺100メートルの半分だけ内側である。
const 中心メートル: f32 = 50.0;

/// 下りが始まる中心からの距離。柵の輪(半径14メートル)も小物の塊もこの内側にあるため、置いたものの接地は下りに触れない。
const 平らな内側の半径メートル: f32 = 40.0;

/// チャンクの端までの距離と、そこまでに下がる高さ。
const 端の距離メートル: f32 = 50.0;
const 落差メートル: f32 = 5.0;

pub(super) fn 大域高さを求める(添字x: i16, 添字z: i16) -> f32 {
    let x = 座標メートル(添字x);
    let z = 座標メートル(添字z);
    庭の起伏(x, z) + 外へ向かう下り(x, z)
}

fn 庭の起伏(x: f32, z: f32) -> f32 {
    0.55 * (x / 31.0).sin() * (z / 27.0).cos() + 0.22 * (x / 11.0 + 0.7).sin() * (z / 13.0 - 0.4).sin()
}

fn 外へ向かう下り(x: f32, z: f32) -> f32 {
    let 距離 = (x - 中心メートル).abs().max((z - 中心メートル).abs());
    let 下りの進み = ((距離 - 平らな内側の半径メートル) / (端の距離メートル - 平らな内側の半径メートル)).max(0.0);
    -落差メートル * 下りの進み * 下りの進み
}

fn 座標メートル(添字: i16) -> f32 {
    f32::from(添字) * 刻みメートル
}
