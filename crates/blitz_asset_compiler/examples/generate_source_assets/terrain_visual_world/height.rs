//! 目視見本の世界の地面の高さ。大域サンプル添字から高さメートルを返す純関数であり、チャンクの区切りを知らない。
//!
//! 振幅の合計は約0.8メートルであり、見本の集落の約1.5メートルよりさらに緩い。この世界の主役は材質見本の球であり、
//! 起伏が大きいと球の映り込みへ地面が大きく入って粗さの比較が難しくなるためである。
//! 完全な平面にしないのは、平面だと地面が単色に塗られて方向光の当たり方の違いが読み取れなくなるためである。
//!
//! 注意: 三角関数の丸めは処理系に依存しうる。生成物をリポジトリへ収めて共有するため、別の処理系で作り直すと末尾ビットが変わることがある。

/// 大域サンプル添字1つあたりの距離。一辺100メートルを64分割した値であり、`terrain_visual_world`の諸元と一致させる。
const 刻みメートル: f32 = 100.0 / 64.0;

pub(super) fn 大域高さを求める(添字x: i16, 添字z: i16) -> f32 {
    let x = 座標メートル(添字x);
    let z = 座標メートル(添字z);
    0.55 * (x / 31.0).sin() * (z / 27.0).cos() + 0.22 * (x / 11.0 + 0.7).sin() * (z / 13.0 - 0.4).sin()
}

fn 座標メートル(添字: i16) -> f32 {
    f32::from(添字) * 刻みメートル
}
