//! 球1つぶんの格子状の頂点と三角形を作る工程。受け取るのは中心と半径、返すのは位置と法線と局所の添字を持つ格子である。
//! 経線と緯線の交点を頂点にし、経度を内側・緯度を外側の昇順で並べる。この並びを固定するため、同じ中心と半径からは常に同じ列を得る。
//! 三角形の頂点順は、辺1と辺2の外積が球の外を向く向きで揃える(地形の面と同じ約束である)。

use super::solid_grid::立体の格子;

/// 経度と緯度の分割数。この細かさなら鏡面の映り込みに多角形の稜線が出ず、8球あわせても頂点はu16の範囲に収まる。
const 経度分割数: usize = 24;
const 緯度分割数: usize = 12;

pub(super) fn 球を作る(中心: [f32; 3], 半径: f32) -> 立体の格子 {
    let 経線数 = 経度分割数 + 1;
    let mut 格子 = 立体の格子::空を作る();
    for 緯度番号 in 0..=緯度分割数 {
        let 天頂角 = std::f32::consts::PI * 割合(緯度番号, 緯度分割数);
        for 経度番号 in 0..=経度分割数 {
            let 方位角 = std::f32::consts::TAU * 割合(経度番号, 経度分割数);
            let 法線 = [天頂角.sin() * 方位角.cos(), 天頂角.cos(), 天頂角.sin() * 方位角.sin()];
            格子.頂点を足す(位置を求める(中心, 半径, 法線), 法線);
        }
    }
    for 緯度番号 in 0..緯度分割数 {
        for 経度番号 in 0..経度分割数 {
            let 左上 = 添字を求める(緯度番号 * 経線数 + 経度番号);
            let 右上 = 左上 + 1;
            let 左下 = 添字を求める((緯度番号 + 1) * 経線数 + 経度番号);
            格子.三角形を足す([左上, 右上, 左下]);
            格子.三角形を足す([右上, 左下 + 1, 左下]);
        }
    }
    格子
}

fn 位置を求める(中心: [f32; 3], 半径: f32, 法線: [f32; 3]) -> [f32; 3] {
    [中心[0] + 半径 * 法線[0], 中心[1] + 半径 * 法線[1], 中心[2] + 半径 * 法線[2]]
}

fn 割合(番号: usize, 分割数: usize) -> f32 {
    実数にする(番号) / 実数にする(分割数)
}

fn 実数にする(値: usize) -> f32 {
    f32::from(u8::try_from(値).unwrap_or_else(|_| panic!("球の分割の番号{値}がu8に収まらない")))
}

fn 添字を求める(値: usize) -> u16 {
    u16::try_from(値).unwrap_or_else(|_| panic!("球の局所頂点番号{値}がu16に収まらない"))
}
