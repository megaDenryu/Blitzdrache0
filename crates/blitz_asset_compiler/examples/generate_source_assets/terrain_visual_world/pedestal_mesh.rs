//! 球の列を載せる台座の箱を作る工程。受け取るのは半幅と半奥行きと深さ、返すのは位置と法線と局所の添字を持つ格子である。
//! 上面を高さ0に置き、そこから下へ深さぶん伸ばす。面ごとに頂点を分けるのは、6つの面が別々の法線を持ち、稜線を丸めないためである。
//! 三角形の頂点順は、辺1と辺2の外積が箱の外を向く向きで揃える(地形の面と同じ約束である)。

use super::solid_grid::立体の格子;

pub(super) fn 台座を作る(半幅: f32, 半奥行き: f32, 深さ: f32) -> 立体の格子 {
    let (右, 左, 手前, 奥, 上, 下) = (半幅, -半幅, 半奥行き, -半奥行き, 0.0, -深さ);
    let mut 格子 = 立体の格子::空を作る();
    面を足す(&mut 格子, [[左, 上, 手前], [右, 上, 手前], [右, 上, 奥], [左, 上, 奥]], [0.0, 1.0, 0.0]);
    面を足す(&mut 格子, [[左, 下, 奥], [右, 下, 奥], [右, 下, 手前], [左, 下, 手前]], [0.0, -1.0, 0.0]);
    面を足す(
        &mut 格子,
        [[左, 下, 手前], [右, 下, 手前], [右, 上, 手前], [左, 上, 手前]],
        [0.0, 0.0, 1.0],
    );
    面を足す(&mut 格子, [[右, 下, 奥], [左, 下, 奥], [左, 上, 奥], [右, 上, 奥]], [0.0, 0.0, -1.0]);
    面を足す(&mut 格子, [[右, 下, 手前], [右, 下, 奥], [右, 上, 奥], [右, 上, 手前]], [1.0, 0.0, 0.0]);
    面を足す(&mut 格子, [[左, 下, 奥], [左, 下, 手前], [左, 上, 手前], [左, 上, 奥]], [-1.0, 0.0, 0.0]);
    格子
}

/// 四隅を外から見て反時計回りに受け取り、2つの三角形へ割る。
fn 面を足す(格子: &mut 立体の格子, 四隅: [[f32; 3]; 4], 法線: [f32; 3]) {
    let 起点 = u16::try_from(格子.頂点数()).unwrap_or_else(|_| panic!("台座の局所頂点番号がu16に収まらない"));
    for 隅 in 四隅 {
        格子.頂点を足す(隅, 法線);
    }
    格子.三角形を足す([起点, 起点 + 1, 起点 + 2]);
    格子.三角形を足す([起点, 起点 + 2, 起点 + 3]);
}
