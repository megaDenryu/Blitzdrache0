//! マップ生成の乱数の種と、その種を起動引数から読む工程。担当するのは種そのものと綴りの解析だけであり、
//! 種から高さをどう作るかは`fox_tour_world::height`が持つ。
//!
//! 種を型で包むのは、同じu32でも格子の添字や個体数と混ぜてはならない量だからである。
//! 種を渡した実行は場所巡りの世界だけを書き出す。既存の検証用の世界を一緒に書き直すと、
//! 判定値を持つ入口の入力が種の指定という無関係な操作で変わりうるためである。

/// マップ生成の乱数の種。同じ種からは必ず同じ高さの並びが出る。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct マップ生成の乱数の種(u32);

impl マップ生成の乱数の種 {
    pub(crate) fn 生成する(値: u32) -> Self {
        Self(値)
    }

    pub(crate) fn 値(self) -> u32 {
        self.0
    }
}

/// 種を導く選択肢の綴り。この綴りの直後の1語が種の値である。
const 選択肢の綴り: &str = "--game-map-seed";

/// 起動引数から種を読む。引数が無ければ種なし、綴りが違うか値が読めなければ失敗である。
/// 知らない引数を無視せず失敗にするのは、綴りを打ち間違えた実行が検証用の世界一式の書き直しへ黙って落ちるためである。
pub(crate) fn 引数一覧から種を読む(引数一覧: &[String]) -> Result<Option<マップ生成の乱数の種>, String> {
    let [] = 引数一覧 else {
        return 種の指定を読む(引数一覧).map(Some);
    };
    Ok(None)
}

fn 種の指定を読む(引数一覧: &[String]) -> Result<マップ生成の乱数の種, String> {
    let [綴り, 値] = 引数一覧 else {
        return Err(format!("引数は{選択肢の綴り}と種の値の2語である"));
    };
    if 綴り != 選択肢の綴り {
        return Err(format!("知らない引数である: {綴り}(選べるのは{選択肢の綴り} <数>だけである)"));
    }
    let 種 = 値
        .parse::<u32>()
        .map_err(|誤り| format!("{選択肢の綴り}の値を32ビットの非負整数として読めない({値}): {誤り}"))?;
    Ok(マップ生成の乱数の種::生成する(種))
}
