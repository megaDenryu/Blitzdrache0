//! 決定的な雑音の画素の生成。担当するのは1画素の色を座標から決めることだけであり、
//! 画像の寸法も書き出し先もこのモジュールは知らない。
//!
//! この素材を対照に選ぶのは、BC1が1ブロックの色を2つの端点が張る1本の線分上の4点だけで表すため、
//! 隣り合う画素の色が無相関に散る絵では線分から外れた色がそのまま誤差になるからである。
//! グラデーションが端点の丸めの誤差を、この素材が線分に載せられない色の誤差を露出する。
//!
//! 疑似乱数を整数の混ぜ合わせだけで作るのは、同じ座標から常に同じ色が出ることを保証するためである。
//! 乱数生成器を持つと種と呼び出し順が値を決めることになり、生成の順序を変えた瞬間に絵が変わる。

/// 混ぜ合わせに使う奇数の乗数。桁を全域へ散らすことだけが役割であり、値そのものに意味は無い。
const 横座標の乗数: u32 = 0x9E37_79B9;
const 縦座標の乗数: u32 = 0x85EB_CA6B;
const 成分番号の乗数: u32 = 0xC2B2_AE35;
const 仕上げの乗数: u32 = 0x2545_F491;

/// 1画素の赤・緑・青・不透明度を座標から決める。3成分は別々の混ぜ合わせから採るため互いに無相関である。
/// 不透明度を255に固定するのは、BC1が不透明度を運ばず、不透明でない画素を持つ画像を焼けないためである。
pub(super) fn 決定的な雑音の画素を求める(x: u32, y: u32) -> image::Rgba<u8> {
    image::Rgba([
        雑音の1成分の符号値を求める(x, y, 0),
        雑音の1成分の符号値を求める(x, y, 1),
        雑音の1成分の符号値を求める(x, y, 2),
        255,
    ])
}

/// 座標と成分番号を混ぜ合わせた32ビットの最下位バイトを符号値として採る。
/// 最下位バイトを取り出す形で書くのは、数値の`as`変換を使わないためである。
fn 雑音の1成分の符号値を求める(x: u32, y: u32, 成分番号: u32) -> u8 {
    let mut 値 = x.wrapping_mul(横座標の乗数) ^ y.wrapping_mul(縦座標の乗数) ^ 成分番号.wrapping_mul(成分番号の乗数);
    値 ^= 値 >> 15;
    値 = 値.wrapping_mul(仕上げの乗数);
    値 ^= 値 >> 13;
    値.to_le_bytes()[0]
}
