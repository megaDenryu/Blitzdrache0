//! 滑らかなグラデーションの画素の生成。担当するのは1画素の色を座標から決めることだけであり、
//! 画像の寸法も書き出し先もこのモジュールは知らない。
//!
//! この素材を対照に選ぶのは、BC1が4x4ブロックの色を2つの端点が張る線分上の4点へ量子化するため、
//! 隣り合う画素の差が小さい絵では端点のRGB565への丸めがそのまま段差(バンディング)として現れるからである。
//! 3成分がそれぞれ別の向きへ変化するため、1成分だけを見て段差を取り逃すことがない。

/// 座標から色を決める割り算の分母。一辺512画素の最大座標が511であるため、両端が0と255へちょうど届く。
const 座標の最大値: u32 = 511;

/// 1画素の赤・緑・青・不透明度を座標から決める。赤は横へ、緑は縦へ、青は対角へ増減する。
/// 不透明度を255に固定するのは、BC1が不透明度を運ばず、不透明でない画素を持つ画像を焼けないためである。
pub(super) fn 滑らかなグラデーションの画素を求める(x: u32, y: u32) -> image::Rgba<u8> {
    let 赤 = 座標を0から255へ引き伸ばす(x);
    let 緑 = 座標を0から255へ引き伸ばす(y);
    let 青 = 255 - 座標を0から255へ引き伸ばす((x + y) / 2);
    image::Rgba([
        上限255で切り詰めて符号値にする(赤),
        上限255で切り詰めて符号値にする(緑),
        上限255で切り詰めて符号値にする(青),
        255,
    ])
}

/// 0から511までの座標を0から255までの符号値の幅へ写す。整数の割り算だけで書くため、同じ座標からは常に同じ値が出る。
fn 座標を0から255へ引き伸ばす(座標: u32) -> u32 {
    座標.min(座標の最大値) * 255 / 座標の最大値
}

/// 255以下と分かっている値を1バイトへ写す。最下位バイトを取り出す形で書くのは、数値の`as`変換を使わないためである。
fn 上限255で切り詰めて符号値にする(値: u32) -> u8 {
    値.min(255).to_le_bytes()[0]
}
