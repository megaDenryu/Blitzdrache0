//! ブロック圧縮の対照シーンの頂点データをglTFのバッファバイト列へ直列化する。
//! 中身は隙間なく左右に並ぶ2枚の板であり、どちらも法線+Zの平面に置く。
//!
//! 区間の並び順(位置→法線→接線→UV→インデックス)と各区間のバイト長は`gltf_json`のbufferViewsへ手動で一致させている。
//!
//! 板を画面より大きく取って隙間を空けないのは、読み戻し画像の全画素を対照のテクスチャが塗るようにするためである。
//! 背景やほかの物体の画素が混じると、2つの方針の絵の差の統計に誤差0の画素が入り、平均が入力と無関係に薄まる。

/// 板2枚を合わせた左右の端。既定カメラは原点から3メートル離れた+Z軸上にあり縦視野角は60度であるため、
/// 画面の縦半分は1.74メートル、横半分は縦半分に画面の横縦比を掛けた長さになる。
/// 横4.0メートル・縦2.4メートルは、横縦比2.3までの窓で画面全体を板が覆う大きさである。
const 左右の端: f32 = 4.0;
const 上下の端: f32 = 2.4;

/// 位置・法線・接線・UV・インデックスを連結した.binの中身を作る。
pub(super) fn バッファバイト列を作る() -> Vec<u8> {
    let インデックス一覧: [u16; 12] = [0, 1, 2, 0, 2, 3, 4, 5, 6, 4, 6, 7];
    let mut バイト列 = Vec::with_capacity(408);
    for 位置 in 板2枚の位置を並べる() {
        f32を並べる(&mut バイト列, &位置);
    }
    for _ in 0..8 {
        f32を並べる(&mut バイト列, &[0.0, 0.0, 1.0]);
    }
    // UのプラスがワールドX、VのプラスがワールドYに一致する構図のため、接線(dPos/dU)=(1,0,0)・w=+1が幾何学的に正しい(判断25)。
    for _ in 0..8 {
        f32を並べる(&mut バイト列, &[1.0, 0.0, 0.0, 1.0]);
    }
    for _ in 0..2 {
        for 座標 in [[0.0f32, 0.0], [1.0, 0.0], [1.0, 1.0], [0.0, 1.0]] {
            f32を並べる(&mut バイト列, &座標);
        }
    }
    for インデックス in インデックス一覧 {
        バイト列.extend_from_slice(&インデックス.to_le_bytes());
    }
    バイト列
}

/// 左の板の4頂点に続いて右の板の4頂点を並べる。どちらも反時計回りで表が+Zを向き、中央の辺を共有して隙間を作らない。
fn 板2枚の位置を並べる() -> [[f32; 3]; 8] {
    [
        [-左右の端, -上下の端, 0.0],
        [0.0, -上下の端, 0.0],
        [0.0, 上下の端, 0.0],
        [-左右の端, 上下の端, 0.0],
        [0.0, -上下の端, 0.0],
        [左右の端, -上下の端, 0.0],
        [左右の端, 上下の端, 0.0],
        [0.0, 上下の端, 0.0],
    ]
}

fn f32を並べる(バイト列: &mut Vec<u8>, 成分一覧: &[f32]) {
    for 成分 in 成分一覧 {
        バイト列.extend_from_slice(&成分.to_le_bytes());
    }
}

/// 位置アクセサが宣言する範囲。`板2枚の位置を並べる`の値域と一致させる。
pub(super) fn 位置の範囲を返す() -> ([f32; 3], [f32; 3]) {
    ([-左右の端, -上下の端, 0.0], [左右の端, 上下の端, 0.0])
}
