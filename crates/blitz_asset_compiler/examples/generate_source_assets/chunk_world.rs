//! チャンク分割された検証用世界の定義と、そのソースアセット一式の書き出し。
//! 世界の広がり(5×5)、一辺長、チャンクごとの名前という世界そのものの決め事をこのモジュールが持ち、
//! 頂点バイト列・glTF文書・目録ソースの各形式は子モジュールが持つ。
//! 参照: `_doc/設計/チャンクストリーミング.md`「検証用チャンク世界」

mod directory_source;
mod geometry;
mod gltf_json;

use std::path::Path;

use blitz_engine::チャンク座標;

/// チャンク格子の一辺長。`_doc/設計/チャンクストリーミング.md`が定める検証用世界の値である。
const 一辺メートル: i32 = 100;
/// XとZの両方をこの範囲で走らせるため、5×5の25チャンクになる。負座標を含めて符号の扱いを実データで検証する。
const 座標最小: i32 = -2;
const 座標最大: i32 = 2;
const 板の半辺: f32 = 0.5;
const 共有バッファファイル名: &str = "chunk_world.bin";
const 目録ソースファイル名: &str = "chunk_directory.txt";

pub(super) fn 書き出す(出力先ディレクトリ: &Path) -> Result<(), String> {
    let 座標一覧 = 座標一覧を作る();
    let 共有バッファ = geometry::共有バッファバイト列を作る(&座標一覧)?;
    書き込む(&出力先ディレクトリ.join(共有バッファファイル名), &共有バッファ)?;
    for (添字, 座標) in 座標一覧.iter().enumerate() {
        let 文書 = gltf_json::文書を作る(添字, *座標, 共有バッファ.len())?;
        書き込む(&出力先ディレクトリ.join(文書ファイル名を作る(*座標)), 文書.as_bytes())?;
    }
    let 目録ソース = directory_source::目録ソースを作る(&座標一覧);
    書き込む(&出力先ディレクトリ.join(目録ソースファイル名), 目録ソース.as_bytes())
}

/// Zを外側、Xを内側に走らせて決定的な並びを作る。目録ソースの行順もこの並びになる。
fn 座標一覧を作る() -> Vec<チャンク座標> {
    let mut 結果 = Vec::new();
    for z in 座標最小..=座標最大 {
        for x in 座標最小..=座標最大 {
            結果.push(チャンク座標::生成する(x, z));
        }
    }
    結果
}

fn 名前を作る(座標: チャンク座標) -> String {
    format!("chunk_x{}_z{}", 座標.x(), 座標.z())
}

fn 文書ファイル名を作る(座標: チャンク座標) -> String {
    format!("{}.gltf", 名前を作る(座標))
}

fn チャンク中心を求める(座標: チャンク座標) -> Result<(f32, f32), String> {
    Ok((軸中心を求める(座標.x())?, 軸中心を求める(座標.z())?))
}

/// 数値のasキャストを使わないため、i16経由のロスレスな`From`でf32へ移す。
/// 検証用世界の座標範囲では中心が-150から250に収まるため、i16への縮小は必ず成功する。
fn 軸中心を求める(軸座標: i32) -> Result<f32, String> {
    let 中心 = 軸座標
        .checked_mul(一辺メートル)
        .and_then(|端| 端.checked_add(一辺メートル / 2))
        .ok_or_else(|| format!("チャンク中心がi32の範囲を超えた: {軸座標}"))?;
    let 狭めた = i16::try_from(中心).map_err(|_| format!("チャンク中心がi16の範囲を超えた: {中心}"))?;
    Ok(f32::from(狭めた))
}

fn 書き込む(パス: &Path, バイト列: &[u8]) -> Result<(), String> {
    std::fs::write(パス, バイト列).map_err(|誤り| format!("{}: {誤り}", パス.display()))
}
