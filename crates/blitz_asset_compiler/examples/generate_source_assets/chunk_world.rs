//! チャンク分割された検証用世界の定義と、そのソースアセット一式の書き出し。
//! 世界の広がり(5×5)、一辺長、チャンクごとの名前という世界そのものの決め事をこのモジュールが持ち、
//! 頂点バイト列・glTF文書の各形式は子モジュールが持つ。
//! 参照: `_doc/設計/チャンクストリーミング.md`「検証用チャンク世界」

mod geometry;
mod gltf_json;

use std::path::Path;

use blitz_engine::チャンク座標;

use crate::directory_source::{目録ソースを作る, 目録項目};

/// XとZの両方をこの範囲で走らせるため、5×5の25チャンクになる。負座標を含めて符号の扱いを実データで検証する。
const 座標最小: i32 = -2;
const 座標最大: i32 = 2;
const 板の半辺: f32 = 0.5;
/// チャンク局所座標での板の中心。チャンクの大域原点はX最小・Z最小の角のため、一辺100メートルの半分だけ内側へ寄せると板がチャンクの中央へ来る。
const 板の局所中心: f32 = 50.0;
const 共有バッファファイル名: &str = "chunk_world.bin";
const 目録ソースファイル名: &str = "chunk_directory.txt";

pub(crate) fn 書き出す(出力先ディレクトリ: &Path) -> Result<(), String> {
    let 座標一覧 = 座標一覧を作る();
    let 共有バッファ = geometry::共有バッファバイト列を作る(座標一覧.len());
    書き込む(&出力先ディレクトリ.join(共有バッファファイル名), &共有バッファ)?;
    let mut 項目一覧 = Vec::new();
    for (添字, 座標) in 座標一覧.iter().enumerate() {
        let 文書 = gltf_json::文書を作る(添字, 共有バッファ.len());
        let ファイル名 = 文書ファイル名を作る(*座標);
        書き込む(&出力先ディレクトリ.join(&ファイル名), 文書.as_bytes())?;
        項目一覧.push(目録項目 {
            座標: *座標,
            アセット識別子: 名前を作る(*座標),
            ソース相対パス: ファイル名,
        });
    }
    書き込む(&出力先ディレクトリ.join(目録ソースファイル名), 目録ソースを作る(&項目一覧).as_bytes())
}

/// Zを外側、Xを内側に走らせて決定的な並びを作る。目録ソースの行順もこの並びになる。
fn 座標一覧を作る() -> Vec<チャンク座標> {
    let mut 結果 = Vec::new();
    for z in 座標最小..=座標最大 {
        for x in 座標最小..=座標最大 {
            結果.push(チャンク座標::生成する(x, z));
        }
    }
    結果
}

fn 名前を作る(座標: チャンク座標) -> String {
    format!("chunk_x{}_z{}", 座標.x(), 座標.z())
}

fn 文書ファイル名を作る(座標: チャンク座標) -> String {
    format!("{}.gltf", 名前を作る(座標))
}

fn 書き込む(パス: &Path, バイト列: &[u8]) -> Result<(), String> {
    std::fs::write(パス, バイト列).map_err(|誤り| format!("{}: {誤り}", パス.display()))
}
