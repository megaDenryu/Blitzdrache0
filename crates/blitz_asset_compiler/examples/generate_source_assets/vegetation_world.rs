//! 植生インスタンスの検証用世界のソースアセット一式。段を1つだけ持つ原型glTFと、段を2つ持つ原型glTFと、
//! それらを指す1チャンクの目録ソースを書き出す。
//! 世界を1チャンクに留めるのは、この世界の役割が「インスタンス群が実際に描けること」の確認であり、
//! 既存の板の世界・地形世界の25チャンクと同じ広がりを持つ必要がないためである。
//!
//! 段を1つだけ持つ原型を残すのは、可視判定と直接インスタンス描画の検収が段の選択を含まない条件で成り立つためである。
//! そちらへ段を足すと、それらの検収の絵が段の選択の結果に左右されるようになる。
//! 段を2つ持つ原型と同じ外形で面だけを細分化した診断用の原型も並べて書き出す(`subdivided`)。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「インスタンス群の表現」

mod geometry;
mod gltf_json;
mod stage_amount;
mod subdivided;

use std::path::Path;

use blitz_engine::チャンク座標;

use crate::directory_source::{目録ソースを作る, 目録項目};
use geometry::直方体諸元;

/// 原型の直方体の水平半辺と高さ。個体が画面上で塊として見え、かつ格子の刻みより十分小さい寸法にする。
const 原型の半辺: f32 = 0.8;
const 原型の高さ: f32 = 3.0;

/// 個体別LODの原型が持つ粗い段。最詳細段より細く低い直方体にすることで、同じ個体でも段が変われば
/// 覆う画素の数と輪郭がはっきり変わり、どの段を描いたかが絵で見分けられる。
const 粗い段の半辺: f32 = 0.3;
const 粗い段の高さ: f32 = 1.0;

const 共有バッファファイル名: &str = "archetype.bin";
const 原型文書ファイル名: &str = "archetype.gltf";
const LOD共有バッファファイル名: &str = "archetype_lod.bin";
const LOD原型文書ファイル名: &str = "archetype_lod.gltf";
const 目録ソースファイル名: &str = "chunk_directory.txt";

/// この世界のチャンクは原点1つだけである。
const チャンクのアセット識別子: &str = "vegetation_chunk";

pub(crate) fn 書き出す(出力先ディレクトリ: &Path) -> Result<(), String> {
    let 最詳細段 = 直方体諸元 {
        半辺: 原型の半辺,
        高さ: 原型の高さ,
    };
    let 粗い段 = 直方体諸元 {
        半辺: 粗い段の半辺,
        高さ: 粗い段の高さ,
    };
    原型を書き出す(出力先ディレクトリ, &[最詳細段], 共有バッファファイル名, 原型文書ファイル名)?;
    原型を書き出す(出力先ディレクトリ, &[最詳細段, 粗い段], LOD共有バッファファイル名, LOD原型文書ファイル名)?;
    subdivided::書き出す(出力先ディレクトリ, &[最詳細段, 粗い段])?;

    let 項目一覧 = vec![目録項目 {
        座標: チャンク座標::生成する(0, 0),
        アセット識別子: チャンクのアセット識別子.to_string(),
        ソース相対パス: 原型文書ファイル名.to_string(),
    }];
    書き込む(&出力先ディレクトリ.join(目録ソースファイル名), 目録ソースを作る(&項目一覧).as_bytes())
}

fn 原型を書き出す(
    出力先ディレクトリ: &Path, 諸元一覧: &[直方体諸元], バッファファイル名: &str, 文書ファイル名: &str
) -> Result<(), String> {
    書き込む(&出力先ディレクトリ.join(バッファファイル名), &geometry::バッファバイト列を作る(諸元一覧))?;
    書き込む(
        &出力先ディレクトリ.join(文書ファイル名),
        gltf_json::文書を作る(諸元一覧, バッファファイル名, geometry::直方体の量).as_bytes(),
    )
}

fn 書き込む(パス: &Path, バイト列: &[u8]) -> Result<(), String> {
    std::fs::write(パス, バイト列).map_err(|誤り| format!("{}: {誤り}", パス.display()))
}
