//! 貼り合わせた高さ場の各チャンクの角の格子点が、元の高さ格子の標本と一致することの検査。

use blitz_asset_compiler::高さ場アセットをコンパイルする;
use blitz_engine::height_field::実行時形式から高さ場を読む;
use blitz_math::大域メートル;

use super::{チャンクの一辺メートル, 地形の世界のソース一覧, 端からの大域添字へ変換する, 端のチャンク};

#[test]
fn 地形の世界の高さ格子から焼いた高さ場が元の標本へ戻る() {
    let ソース一覧 = 地形の世界のソース一覧();
    assert_eq!(ソース一覧.len(), 25);
    let Ok(コンパイル結果) = 高さ場アセットをコンパイルする(&ソース一覧) else {
        panic!("地形の世界の高さ場を焼けなかった");
    };
    assert_eq!(コンパイル結果.ソース依存一覧.len(), 25);
    let Ok(高さ場) = 実行時形式から高さ場を読む(&コンパイル結果.実行時バイト列) else {
        panic!("焼いた高さ場を実行時形式から復元できなかった");
    };

    let 諸元 = 高さ場.諸元();
    let チャンク一辺の格子点数 = (諸元.東方向の格子点数() - 1) / 5;
    assert_eq!(諸元.東方向の格子点数(), 諸元.南方向の格子点数());
    assert_eq!(
        諸元.格子原点の東成分(),
        大域メートル::生成する(f64::from(-端のチャンク) * チャンクの一辺メートル)
    );

    // 各チャンクの角の格子点を、元の高さ格子から直接引いた値と突き合わせる。
    for ソース in &ソース一覧 {
        let チャンク = ソース.座標();
        let Ok(読み込んだチャンク) = ソース.読み込む() else {
            panic!("高さ格子を読めなかった: チャンク({}, {})", チャンク.x(), チャンク.z());
        };
        let 格子 = 読み込んだチャンク.格子();
        let 東の大域添字 = 端からの大域添字へ変換する(チャンク.x()) * チャンク一辺の格子点数;
        let 南の大域添字 = 端からの大域添字へ変換する(チャンク.z()) * チャンク一辺の格子点数;
        let Ok(貼り合わせた高さ) = 高さ場.格子点の高さ(東の大域添字, 南の大域添字) else {
            panic!("貼り合わせた高さ場の角の格子点を参照できなかった");
        };
        let Ok(元の高さ) = 格子.高さ(0, 0) else {
            panic!("元の高さ格子の角の格子点を参照できなかった");
        };
        assert_eq!(
            貼り合わせた高さ.値(),
            元の高さ,
            "チャンク({}, {})の角が食い違う",
            チャンク.x(),
            チャンク.z()
        );
    }
}
