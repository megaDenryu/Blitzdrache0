//! 植生の原型glTF→コンパイル→実行時形式の往復テスト: `cargo xtask gen-source-assets`で生成済みの
//! assets/vegetation_world/ を実際に読み、同一入力から同一バイト列が出ることと、焼いた群の構造を検証する。
//!
//! 注意: `cargo test`のテストバイナリはパッケージディレクトリを作業ディレクトリとして
//! 実行される（リポジトリルートではない）ため、`CARGO_MANIFEST_DIR`からの相対パスで
//! リポジトリルート直下のassets/を参照する。

use std::path::PathBuf;

use blitz_asset_compiler::{テクスチャ格納方針, 植生チャンクをコンパイルする};
use blitz_engine::{アセットID, カタログ, チャンク座標, 実行時形式からシーンを読む, 描画形状};

const 個体数: usize = 64;
const 原型の頂点数: usize = 24;

fn リポジトリルートからのパス(相対パス: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..").join(相対パス)
}

fn カタログを作る() -> (カタログ, アセットID) {
    let Ok(id) = アセットID::生成する("vegetation_chunk") else {
        panic!("検証用アセットIDを生成できなかった");
    };
    let mut カタログ = カタログ::空を作る();
    カタログ.登録する(id.clone(), リポジトリルートからのパス("assets/vegetation_world/archetype.gltf"));
    (カタログ, id)
}

#[test]
fn 同じ原型と同じ個体数から同じバイト列を焼く() {
    let (カタログ, id) = カタログを作る();
    let 座標 = チャンク座標::生成する(0, 0);
    let 一回目 = match 植生チャンクをコンパイルする(&カタログ, &id, 座標, 個体数, テクスチャ格納方針::全てRGBA8) {
        Ok(結果) => 結果,
        Err(誤り) => panic!("植生チャンクのコンパイルに失敗した(cargo xtask gen-source-assetsで生成済みか確認): {誤り}"),
    };
    let Ok(二回目) = 植生チャンクをコンパイルする(&カタログ, &id, 座標, 個体数, テクスチャ格納方針::全てRGBA8)
    else {
        panic!("2回目の植生チャンクのコンパイルに失敗した");
    };
    assert_eq!(一回目.実行時バイト列, 二回目.実行時バイト列);
    assert_eq!(一回目.メタデータ.個体数, 64);
    assert_eq!(一回目.メタデータ.頂点数, 24);
}

#[test]
fn 個体数を変えるとバイト列も変わる() {
    let (カタログ, id) = カタログを作る();
    let 座標 = チャンク座標::生成する(0, 0);
    let Ok(少ない) = 植生チャンクをコンパイルする(&カタログ, &id, 座標, 4, テクスチャ格納方針::全てRGBA8) else {
        panic!("4個体の植生チャンクのコンパイルに失敗した");
    };
    let Ok(多い) = 植生チャンクをコンパイルする(&カタログ, &id, 座標, 個体数, テクスチャ格納方針::全てRGBA8)
    else {
        panic!("64個体の植生チャンクのコンパイルに失敗した");
    };
    assert_ne!(少ない.実行時バイト列, 多い.実行時バイト列);
    // 個体1件は平行移動3・回転4・スケール3のf32で40バイトを占める。原型と境界は個体数に依らないため差はここだけになる。
    assert_eq!(多い.実行時バイト列.len() - 少ない.実行時バイト列.len(), (個体数 - 4) * 40);
}

#[test]
fn 焼いた群を実行時形式から復元できる() {
    let (カタログ, id) = カタログを作る();
    let 座標 = チャンク座標::生成する(0, 0);
    let Ok(結果) = 植生チャンクをコンパイルする(&カタログ, &id, 座標, 個体数, テクスチャ格納方針::全てRGBA8)
    else {
        panic!("植生チャンクのコンパイルに失敗した");
    };
    let Ok(シーン) = 実行時形式からシーンを読む(&結果.実行時バイト列) else {
        panic!("植生チャンクの実行時形式を復元できなかった");
    };
    assert_eq!(シーン.描画対象一覧().len(), 1);
    let 描画形状::インスタンス群(群) = シーン.先頭の描画対象().形状() else {
        panic!("焼いた形状がインスタンス群でない");
    };
    assert_eq!(群.個体数(), 個体数);
    assert_eq!(群.原型().段数(), 1);
    assert_eq!(群.原型().最詳細メッシュ().頂点一覧.len(), 原型の頂点数);
    let 包囲 = 群.境界().群の包囲領域();
    for 配置 in 群.配置一覧() {
        let [x, _, z] = 配置.平行移動();
        assert!(包囲.最小()[0] <= x && x <= 包囲.最大()[0], "個体Xが群の包囲領域の外にある");
        assert!(包囲.最小()[2] <= z && z <= 包囲.最大()[2], "個体Zが群の包囲領域の外にある");
    }
}
