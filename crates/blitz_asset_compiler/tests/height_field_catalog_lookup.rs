//! 焼いた高さ場を固定の安定IDでカタログへ登録し、実行時の読み口がその1件を見つけて問い合わせに答えるまでの通し検査。
//! 焼く側と読む側が同じ綴りの安定IDを指していることを、この検査が反証する。
//!
//! 注意: `cargo test`のテストバイナリはパッケージディレクトリを作業ディレクトリとして実行されるため、
//! `CARGO_MANIFEST_DIR`からの相対パスでリポジトリルート直下のassets/を参照する。

use std::path::PathBuf;

use blitz_asset_compiler::{
    チャンクの高さ格子ソース, チャンク目録ソースを読み込む, 高さ場アセットをコンパイルする, 高さ格子のファイル
};
use blitz_engine::height_field::{世界の高さ場の安定IDの綴り, 地表高さの問い合わせ結果, 高さ場の読み口};
use blitz_engine::{アセットID, カタログ};
use blitz_math::{大域メートル, 大域ワールド位置};

fn 地形の世界のソース一覧() -> Vec<チャンクの高さ格子ソース> {
    let 目録ソースパス = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join("assets/terrain_world/chunk_directory.txt");
    let 目録ソース = match チャンク目録ソースを読み込む(&目録ソースパス) {
        Ok(目録ソース) => 目録ソース,
        Err(誤り) => panic!("チャンク目録ソースの読込に失敗した(cargo xtask gen-source-assetsで生成済みか確認): {誤り}"),
    };
    目録ソース
        .項目一覧()
        .iter()
        .map(|項目| {
            チャンクの高さ格子ソース::生成する(
                項目.チャンク(),
                高さ格子のファイル::パスから作る(目録ソースパス.with_file_name(項目.ソース相対パス())),
            )
        })
        .collect()
}

fn 出力先を用意する() -> PathBuf {
    let 出力先 = std::env::temp_dir().join("blitzdrache0_height_field_catalog_lookup");
    if let Err(誤り) = std::fs::create_dir_all(&出力先) {
        panic!("検査用の出力先を作れなかった: {誤り}");
    }
    出力先
}

#[test]
fn 安定idで登録した高さ場を読み口が見つけて答える() {
    let Ok(コンパイル結果) = 高さ場アセットをコンパイルする(&地形の世界のソース一覧()) else {
        panic!("地形の世界の高さ場を焼けなかった");
    };
    assert!(コンパイル結果.メタデータ.高さ場の標本数.値() > 0);
    assert_eq!(
        コンパイル結果.メタデータ.高さ場の標本数.格納バイト数を求める(),
        Some(コンパイル結果.メタデータ.高さ場の標本数.値() * 4)
    );
    let 出力パス = 出力先を用意する().join(format!("{}.blitzasset", 世界の高さ場の安定IDの綴り));
    if let Err(誤り) = std::fs::write(&出力パス, &コンパイル結果.実行時バイト列) {
        panic!("焼いた高さ場を書き出せなかった: {誤り}");
    }

    let mut カタログ = カタログ::空を作る();
    let Ok(id) = アセットID::生成する(世界の高さ場の安定IDの綴り) else {
        panic!("世界の高さ場の安定IDを組み立てられなかった");
    };
    カタログ.詳細を登録する(id, 出力パス, コンパイル結果.ソース依存一覧, コンパイル結果.メタデータ);

    let Ok(読み口) = 高さ場の読み口::カタログから読み込む(&カタログ) else {
        panic!("カタログから高さ場を読めなかった");
    };
    let 原点 = 大域ワールド位置::原点();
    let 地表高さの問い合わせ結果::地表高さ(高さ) = 読み口.大域の水平位置から地表高さを求める(原点) else {
        panic!("登録した高さ場が読み口の枝に現れなかった");
    };
    assert!(高さ.値().is_finite(), "地表高さが有限でない");
}

/// 反証: 高さ場を登録していないカタログが「高さ場を持つ世界」になると、既存の検収の世界でキツネの高さが動く。
#[test]
fn 高さ場を登録していないカタログは高さ場を持たない世界になる() {
    let Ok(読み口) = 高さ場の読み口::カタログから読み込む(&カタログ::空を作る()) else {
        panic!("空のカタログで高さ場の読み口を作れなかった");
    };
    assert_eq!(読み口, 高さ場の読み口::高さ場を持たない世界);
    let 位置 = 大域ワールド位置::生成する(大域メートル::生成する(1.0), 大域メートル::生成する(0.0), 大域メートル::生成する(2.0));
    assert_eq!(
        読み口.大域の水平位置から地表高さを求める(位置),
        地表高さの問い合わせ結果::高さ場を持たない世界
    );
}
