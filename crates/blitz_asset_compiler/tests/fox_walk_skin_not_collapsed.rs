//! Fox.glb(判断49)の回帰テスト: Walkクリップ評価後に平行移動チャンネルを持たない
//! ジョイントが親ジョイントの位置へ潰れていないことを確認する。判断49修正前は
//! 「チャンネルが無いジョイントは恒等TRS」だったため、回転チャンネルのみ(または
//! チャンネル自体が無い)ジョイントの平行移動が全て0になり、親位置に厳密一致して
//! 骨格が潰れる欠陥があった。`CARGO_MANIFEST_DIR`基準の相対パスでリポジトリ直下の
//! assets/を参照する(`cargo xtask fetch-assets`で取得済みが前提)。

use std::path::PathBuf;

use blitz_asset_compiler::{ソースシーンを読み込む, テクスチャ格納方針};
use blitz_engine::{アセットID, カタログ, スキンデータ, チャンク座標, 姿勢, 姿勢を評価する};

fn リポジトリルートからのパス(相対パス: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..").join(相対パス)
}

fn 試験用カタログ() -> (カタログ, アセットID) {
    let id = match アセットID::生成する("fox") {
        Ok(id) => id,
        Err(誤り) => panic!("試験用IDの生成に失敗した: {誤り}"),
    };
    let mut カタログ = カタログ::空を作る();
    カタログ.登録する(id.clone(), リポジトリルートからのパス("assets/samples/Fox/Fox.glb"));
    (カタログ, id)
}

/// スキン行列(逆バインド適用後)ではなく、関節そのもののグローバル平行移動を求める。
/// 逆バインド行列はバインド時の姿勢を打ち消す変換であり「骨格が潰れているか」の
/// 判定には無関係なノイズを混ぜてしまうため、この検証には使わない。
fn グローバル平行移動一覧を計算する(スキン: &スキンデータ, 姿勢: &姿勢) -> Vec<[f32; 3]> {
    let mut グローバル一覧 = Vec::with_capacity(スキン.ジョイント一覧.len());
    for (添字, ジョイント) in スキン.ジョイント一覧.iter().enumerate() {
        let ローカル行列 = 姿勢.関節(添字).へ変換する();
        let グローバル行列 = match ジョイント.親添字 {
            Some(親) => ローカル行列.合成する(グローバル一覧[親]),
            None => ローカル行列,
        };
        グローバル一覧.push(グローバル行列);
    }
    グローバル一覧
        .iter()
        .map(|変換| {
            let 配列 = 変換.gpu境界用列優先配列();
            [配列[3][0], 配列[3][1], 配列[3][2]]
        })
        .collect()
}

fn 距離(a: [f32; 3], b: [f32; 3]) -> f32 {
    let 差 = [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
    (差[0] * 差[0] + 差[1] * 差[1] + 差[2] * 差[2]).sqrt()
}

#[test]
fn walk評価で平行移動チャンネルの無い関節は親位置へ潰れない() {
    let (カタログ, id) = 試験用カタログ();
    let シーン = match ソースシーンを読み込む(&カタログ, &id, チャンク座標::生成する(0, 0), テクスチャ格納方針::全てRGBA8)
    {
        Ok(シーン) => シーン,
        Err(誤り) => panic!("assets/samples/Fox/Fox.glbの読込に失敗した(cargo xtask fetch-assetsで取得済みか確認): {誤り}"),
    };
    let スキン = match &シーン.スキン {
        Some(スキン) => スキン,
        None => panic!("Fox.glbにはスキンがあるはず"),
    };
    let walkクリップ = シーン.アニメーション一覧.iter().find(|c| c.名前 == "Walk");
    let walkクリップ = match walkクリップ {
        Some(クリップ) => クリップ,
        None => panic!("Fox.glbにはWalkクリップがあるはず"),
    };
    let 姿勢 = 姿勢を評価する(walkクリップ, スキン, blitz_math::秒::生成する(0.3));
    let 平行移動一覧 = グローバル平行移動一覧を計算する(スキン, &姿勢);

    // 平行移動チャンネルを持たない(=バインド時TRSの平行移動が既定値として使われるべき)
    // 関節について、親関節との距離の最大値を求める。判断49修正前はこの距離が
    // 全関節でほぼ0になっていた(親に潰れる欠陥)。
    let mut 最大親子距離 = 0.0f32;
    for (添字, チャンネル) in walkクリップ.ジョイントチャンネル一覧.iter().enumerate() {
        if チャンネル.平行移動.is_some() {
            continue;
        }
        let Some(親添字) = スキン.ジョイント一覧[添字].親添字 else {
            continue;
        };
        let 距離 = 距離(平行移動一覧[添字], 平行移動一覧[親添字]);
        最大親子距離 = 最大親子距離.max(距離);
    }
    println!("[診断] 平行移動チャンネル無し関節の親子間最大距離 = {最大親子距離}");
    assert!(最大親子距離 > 5.0, "親位置に潰れていないはず(親子間最大距離): {最大親子距離}");
}
