//! 焼いた地表層テクスチャ集を固定の安定IDでカタログへ登録し、実行時の読み口がその1件を見つけるまでの通し検査。
//! 焼く側と読む側が同じ綴りの安定IDを指していることを、この検査が反証する。
//!
//! 注意: `cargo test`のテストバイナリはパッケージディレクトリを作業ディレクトリとして実行されるため、
//! `CARGO_MANIFEST_DIR`からの相対パスでリポジトリルート直下のassets/を参照する。

#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

use std::path::PathBuf;

use blitz_asset_compiler::{
    ソースルート, テクスチャ格納方針, 地表層タイルの置き場, 地表層テクスチャ集アセットをコンパイルする, 地表材質の層割当
};
use blitz_engine::surface_layer_textures::{世界の地表層テクスチャ集の安定IDの綴り, 地表層テクスチャ集の読み口};
use blitz_engine::{アセットID, カタログ};

fn 出力先を用意する() -> PathBuf {
    let 出力先 = std::env::temp_dir().join("blitzdrache0_surface_layer_texture_set_catalog_lookup");
    std::fs::create_dir_all(&出力先).unwrap();
    出力先
}

#[test]
fn 安定idで登録した地表層テクスチャ集を読み口が見つける() {
    let ソースルート = ソースルート::生成する(PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../assets"));
    let 置き場 = 地表層タイルの置き場::ソースルートの下に作る(&ソースルート);
    assert!(置き場.存在するか(), "タイルの置き場が無い(cargo xtask gen-source-assetsで生成済みか確認)");
    let コンパイル結果 =
        地表層テクスチャ集アセットをコンパイルする(&置き場, &地表材質の層割当::既定を作る(), テクスチャ格納方針::全てRGBA8).unwrap();
    assert!(コンパイル結果.メタデータ.テクスチャ格納バイト数 > 0);
    assert_eq!(コンパイル結果.ソース依存一覧.len(), 4);

    let 出力パス = 出力先を用意する().join(format!("{}.blitzasset", 世界の地表層テクスチャ集の安定IDの綴り));
    std::fs::write(&出力パス, &コンパイル結果.実行時バイト列).unwrap();

    let mut カタログ = カタログ::空を作る();
    let id = アセットID::生成する(世界の地表層テクスチャ集の安定IDの綴り).unwrap();
    カタログ.詳細を登録する(id, 出力パス, コンパイル結果.ソース依存一覧, コンパイル結果.メタデータ);

    let 地表層テクスチャ集の読み口::テクスチャ集を持つ世界(テクスチャ集) =
        地表層テクスチャ集の読み口::カタログから読み込む(&カタログ).unwrap()
    else {
        panic!("登録した地表層テクスチャ集が読み口の枝に現れなかった");
    };
    assert_eq!(テクスチャ集.層のタイル(0).材質名().綴り(), "grass_a");
    assert_eq!(テクスチャ集.層のタイル(3).材質名().綴り(), "sand_a");
}

/// 反証: 地表層テクスチャ集を登録していないカタログが「持つ世界」になると、既存の検収の世界の絵が変わる。
#[test]
fn 登録していないカタログはテクスチャ集を持たない世界になる() {
    assert_eq!(
        地表層テクスチャ集の読み口::カタログから読み込む(&カタログ::空を作る()).unwrap(),
        地表層テクスチャ集の読み口::テクスチャ集を持たない世界
    );
}
