//! 目録ソース→コンパイル→版付きチャンク目録の往復テスト: `cargo xtask gen-source-assets`で生成済みの
//! assets/chunk_world/ を実際に読み、25チャンクの座標解決とチャンク局所座標での配置を検証する。
//!
//! 注意: `cargo test`のテストバイナリはパッケージディレクトリを作業ディレクトリとして
//! 実行される（リポジトリルートではない）ため、`CARGO_MANIFEST_DIR`からの相対パスで
//! リポジトリルート直下のassets/を参照する。

use std::path::PathBuf;

use blitz_asset_compiler::{
    ソースアセットのコンパイル係, チャンク目録ソースを読み込む, テクスチャ格納方針, 種の由来, 配置の種
};
use blitz_engine::{
    カタログ, チャンク座標, チャンク目録, チャンク目録を実行時形式へ格納する, 実行時形式からシーンを読む, 実行時形式からチャンク目録を読む,
};

const 検証対象チャンク: (i32, i32) = (-2, 1);
/// 頂点はチャンク局所座標で焼く。一辺100mの格子では板の中心が(50, 50)であり、世界での配置は描画の基準原点が担う。
const 板の局所中心: (f32, f32) = (50.0, 50.0);
const 板の半辺: f32 = 0.5;

fn リポジトリルートからのパス(相対パス: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..").join(相対パス)
}

#[test]
fn 検証用チャンク世界の目録と配置を往復する() {
    let 目録ソースパス = リポジトリルートからのパス("assets/chunk_world/chunk_directory.txt");
    let 目録ソース = match チャンク目録ソースを読み込む(&目録ソースパス) {
        Ok(目録ソース) => 目録ソース,
        Err(誤り) => panic!("チャンク目録ソースの読込に失敗した(cargo xtask gen-source-assetsで生成済みか確認): {誤り}"),
    };
    assert_eq!(目録ソース.一辺().f32値(), 100.0);
    let チャンク一辺 = 目録ソース.一辺();
    let 項目一覧 = 目録ソース.項目一覧();
    assert_eq!(項目一覧.len(), 25);

    let mut カタログ = カタログ::空を作る();
    let mut 目録 = チャンク目録::空を作る(チャンク一辺);
    for 項目 in &項目一覧 {
        let ソースパス = 目録ソースパス.with_file_name(項目.ソース相対パス());
        カタログ.登録する(項目.アセット().clone(), ソースパス);
        if let Err(誤り) = 目録.登録する(項目.チャンク(), 項目.アセット().clone()) {
            panic!("目録ソースが同じ座標を二重に宣言している: {誤り}");
        }
    }
    assert_eq!(目録.件数(), 25);

    負座標のチャンクをチャンク局所座標で配置する(&カタログ, &目録);
    版付き目録を往復する(&目録);
}

fn 負座標のチャンクをチャンク局所座標で配置する(カタログ: &カタログ, 目録: &チャンク目録) {
    let 座標 = チャンク座標::生成する(検証対象チャンク.0, 検証対象チャンク.1);
    let Some(アセット) = 目録.アセットを参照する(座標) else {
        panic!("負座標のチャンクが目録に無かった");
    };
    let コンパイル結果 = match ソースアセットのコンパイル係::生成する(
        カタログ,
        テクスチャ格納方針::全てRGBA8,
        配置の種::種の由来から作る(種の由来::種を持たない),
    )
    .ソースシーンをコンパイルする(アセット, 座標)
    {
        Ok(結果) => 結果,
        Err(誤り) => panic!("チャンクのコンパイルに失敗した: {誤り}"),
    };
    let Ok(シーン) = 実行時形式からシーンを読む(&コンパイル結果.実行時バイト列) else {
        panic!("チャンクの実行時形式を復元できなかった");
    };
    assert_eq!(シーン.描画対象一覧().len(), 1);
    let 描画対象 = シーン.先頭の描画対象();
    assert_eq!(描画対象.所有チャンク(), 座標);

    let (中心x, 中心z) = 板の局所中心;
    for 頂点 in &描画対象.形状().最詳細メッシュ().頂点一覧 {
        let 位置 = 頂点.位置;
        assert!((位置[0] - 中心x).abs() <= 板の半辺, "頂点Xが板の局所中心から離れている: {位置:?}");
        assert_eq!(位置[1], 0.0);
        assert!((位置[2] - 中心z).abs() <= 板の半辺, "頂点Zが板の局所中心から離れている: {位置:?}");
    }
}

fn 版付き目録を往復する(目録: &チャンク目録) {
    let Ok(バイト列) = チャンク目録を実行時形式へ格納する(目録) else {
        panic!("チャンク目録を実行時形式へ格納できなかった");
    };
    let Ok(復元) = 実行時形式からチャンク目録を読む(&バイト列) else {
        panic!("実行時形式からチャンク目録を復元できなかった");
    };
    assert_eq!(復元.件数(), 25);
    for (座標, アセット) in 目録.全登録を走査する() {
        assert_eq!(復元.アセットを参照する(座標), Some(アセット));
    }
    assert!(
        復元.アセットを参照する(チャンク座標::生成する(3, 0)).is_none(),
        "世界の外側の座標は目録に無く、不在は正常系である"
    );
}
