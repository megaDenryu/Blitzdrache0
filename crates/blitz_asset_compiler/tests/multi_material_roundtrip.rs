//! 段Aの検収: 複数材質のglbをアセットコンパイラが最新版へ焼き、実行時ローダーが読んで往復が一致することを確かめる。
//! 試験材料は最小のGLBをコードから組み立てる。実アセットの受入はBlender段4の領分であり、ここでは形式の往復だけを見る。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「段階導入」A段

mod multi_material_fixture;

use blitz_asset_compiler::{ソースアセットのコンパイル係, テクスチャ格納方針, 種の由来, 配置の種};
use blitz_engine::{
    アセットID, カタログ, チャンク座標, マテリアルデータ, 実行時形式からシーンを読む, 描画形状
};
use multi_material_fixture as fixture;

fn 試験用カタログ() -> (カタログ, アセットID) {
    let id = match アセットID::生成する("multi_material") {
        Ok(id) => id,
        Err(誤り) => panic!("試験用IDの生成に失敗した: {誤り}"),
    };
    let mut カタログ = カタログ::空を作る();
    カタログ.登録する(id.clone(), fixture::glbを書き出す("multi_material"));
    (カタログ, id)
}

fn 焼いたバイト列とソースシーン() -> (Vec<u8>, blitz_engine::シーンデータ) {
    let (カタログ, id) = 試験用カタログ();
    let コンパイル係 = ソースアセットのコンパイル係::生成する(
        &カタログ,
        テクスチャ格納方針::全てRGBA8,
        配置の種::種の由来から作る(種の由来::種を持たない),
    );
    let 所有チャンク = チャンク座標::生成する(0, 0);
    let コンパイル済み = match コンパイル係.ソースシーンをコンパイルする(&id, 所有チャンク) {
        Ok(値) => 値,
        Err(誤り) => panic!("複数材質のglbをコンパイルできなかった: {誤り}"),
    };
    let ソースシーン = match コンパイル係.ソースシーンを読み込む(&id, 所有チャンク) {
        Ok(値) => 値,
        Err(誤り) => panic!("複数材質のglbを読み込めなかった: {誤り}"),
    };
    (コンパイル済み.実行時バイト列, ソースシーン)
}

fn 読み戻す() -> blitz_engine::シーンデータ {
    let (バイト列, _) = 焼いたバイト列とソースシーン();
    match 実行時形式からシーンを読む(&バイト列) {
        Ok(値) => 値,
        Err(誤り) => panic!("焼いた版5のバイト列を読み戻せなかった: {誤り}"),
    }
}

#[test]
fn 複数材質のglbが版5で往復する() {
    let (バイト列, ソースシーン) = 焼いたバイト列とソースシーン();
    assert_eq!(バイト列[8..12], 5_u32.to_le_bytes());
    let 読み取り = match 実行時形式からシーンを読む(&バイト列) {
        Ok(値) => 値,
        Err(誤り) => panic!("焼いた版5のバイト列を読み戻せなかった: {誤り}"),
    };
    assert_eq!(読み取り.描画対象一覧().len(), 1);
    assert_eq!(読み取り.先頭の描画対象().形状(), ソースシーン.先頭の描画対象().形状());
    assert_eq!(読み取り.先頭の描画対象().材質集合(), ソースシーン.先頭の描画対象().材質集合());
}

#[test]
fn 二つのプリミティブがインデックス区間とスロットを分けて持つ() {
    let 読み取り = 読み戻す();
    let 描画形状::通常メッシュ(メッシュ) = 読み取り.先頭の描画対象().形状() else {
        panic!("複数材質のglbが通常メッシュとして読めなかった");
    };
    assert_eq!(メッシュ.頂点一覧.len(), 6);
    assert_eq!(メッシュ.インデックス一覧, vec![0, 1, 2, 3, 4, 5]);
    assert_eq!(メッシュ.プリミティブ列.len(), 2);
    assert_eq!(メッシュ.プリミティブ列[0].インデックス開始, 0);
    assert_eq!(メッシュ.プリミティブ列[0].インデックス数, 3);
    assert_eq!(メッシュ.プリミティブ列[0].頂点基準, 0);
    assert_eq!(メッシュ.プリミティブ列[0].材質スロット.番号を返す(), 0);
    assert_eq!(メッシュ.プリミティブ列[1].インデックス開始, 3);
    assert_eq!(メッシュ.プリミティブ列[1].インデックス数, 3);
    assert_eq!(メッシュ.プリミティブ列[1].頂点基準, 0);
    assert_eq!(メッシュ.プリミティブ列[1].材質スロット.番号を返す(), 1);
}

#[test]
fn 材質集合が入力の2材質をスロット順に持つ() {
    let 読み取り = 読み戻す();
    let 材質集合 = 読み取り.先頭の描画対象().材質集合();
    assert_eq!(材質集合.件数(), 2);
    let マテリアルデータ::金属粗さPBR(スロット0) = &材質集合.割当一覧()[0].マテリアル;
    let マテリアルデータ::金属粗さPBR(スロット1) = &材質集合.割当一覧()[1].マテリアル;
    assert_eq!(材質集合.割当一覧()[0].スロット.番号を返す(), 0);
    assert_eq!(材質集合.割当一覧()[1].スロット.番号を返す(), 1);
    assert_eq!(スロット0.ベースカラー係数, [0.8, 0.3, 0.2, 1.0]);
    assert_eq!(スロット0.金属度係数, 0.5);
    assert_eq!(スロット1.ベースカラー係数, [0.1, 0.7, 0.9, 1.0]);
    assert_eq!(スロット1.金属度係数, 0.25);
    assert_eq!(スロット0.特徴集合().生値(), 0);
    assert_eq!(スロット1.特徴集合().生値(), 0);
}
