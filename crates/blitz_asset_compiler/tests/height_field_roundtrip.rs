//! 高さ格子→高さ場アセット→実行時読込→問い合わせの往復テスト。`cargo xtask gen-source-assets`で生成済みの
//! assets/terrain_world/ の25チャンクを実際に読み、貼り合わせた高さ場が元の格子の標本へ戻ることと、
//! 同じ入力から同じバイト列が出ることを確かめる。
//!
//! 注意: `cargo test`のテストバイナリはパッケージディレクトリを作業ディレクトリとして実行されるため、
//! `CARGO_MANIFEST_DIR`からの相対パスでリポジトリルート直下のassets/を参照する。

use std::path::PathBuf;

use blitz_asset_compiler::{チャンク目録ソースを読み込む, 高さ場アセットをコンパイルする, 高さ格子を読み込む};
use blitz_engine::height_field::実行時形式から高さ場を読む;
use blitz_engine::チャンク座標;
use blitz_math::{大域メートル, 大域ワールド位置};

/// 地形の世界は東西南北とも-2から2までの25チャンクである。
const 端のチャンク: i32 = 2;
/// 高さ格子の切り出しに使っている1チャンクの一辺。
const チャンクの一辺メートル: f64 = 100.0;

fn リポジトリルートからのパス(相対パス: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..").join(相対パス)
}

fn 地形の世界のソース一覧() -> Vec<(チャンク座標, PathBuf)> {
    let 目録ソースパス = リポジトリルートからのパス("assets/terrain_world/chunk_directory.txt");
    let 項目一覧 = match チャンク目録ソースを読み込む(&目録ソースパス) {
        Ok(一覧) => 一覧,
        Err(誤り) => panic!("チャンク目録ソースの読込に失敗した(cargo xtask gen-source-assetsで生成済みか確認): {誤り}"),
    };
    項目一覧
        .iter()
        .map(|項目| (項目.チャンク(), 目録ソースパス.with_file_name(項目.ソース相対パス())))
        .collect()
}

#[test]
fn 地形の世界の高さ格子から焼いた高さ場が元の標本へ戻る() {
    let ソース一覧 = 地形の世界のソース一覧();
    assert_eq!(ソース一覧.len(), 25);
    let Ok(コンパイル結果) = 高さ場アセットをコンパイルする(&ソース一覧) else {
        panic!("地形の世界の高さ場を焼けなかった");
    };
    assert_eq!(コンパイル結果.ソース依存一覧.len(), 25);
    let Ok(高さ場) = 実行時形式から高さ場を読む(&コンパイル結果.実行時バイト列) else {
        panic!("焼いた高さ場を実行時形式から復元できなかった");
    };

    let 諸元 = 高さ場.諸元();
    let チャンク一辺の格子点数 = (諸元.東方向の格子点数() - 1) / 5;
    assert_eq!(諸元.東方向の格子点数(), 諸元.南方向の格子点数());
    assert_eq!(
        諸元.格子原点の東成分(),
        大域メートル::生成する(f64::from(-端のチャンク) * チャンクの一辺メートル)
    );

    // 各チャンクの角の格子点を、元の高さ格子から直接引いた値と突き合わせる。
    for (チャンク, ソースパス) in &ソース一覧 {
        let Ok(格子) = 高さ格子を読み込む(ソースパス) else {
            panic!("高さ格子を読めなかった: {}", ソースパス.display());
        };
        let 東の大域添字 = u32::try_from(チャンク.x() + 端のチャンク).unwrap_or_default() * チャンク一辺の格子点数;
        let 南の大域添字 = u32::try_from(チャンク.z() + 端のチャンク).unwrap_or_default() * チャンク一辺の格子点数;
        let Ok(貼り合わせた高さ) = 高さ場.格子点の高さ(東の大域添字, 南の大域添字) else {
            panic!("貼り合わせた高さ場の角の格子点を引けなかった");
        };
        let Ok(元の高さ) = 格子.高さ(0, 0) else {
            panic!("元の高さ格子の角の格子点を引けなかった");
        };
        assert_eq!(
            貼り合わせた高さ.値(),
            元の高さ,
            "チャンク({}, {})の角が食い違う",
            チャンク.x(),
            チャンク.z()
        );
    }
}

#[test]
fn 同じソースから同じバイト列を焼く() {
    let ソース一覧 = 地形の世界のソース一覧();
    let (Ok(一回目), Ok(二回目)) = (高さ場アセットをコンパイルする(&ソース一覧), 高さ場アセットをコンパイルする(&ソース一覧))
    else {
        panic!("地形の世界の高さ場を2回焼けなかった");
    };
    assert_eq!(一回目.実行時バイト列, 二回目.実行時バイト列);
}

#[test]
fn 高さ場の広がりの外の問い合わせを拒む() {
    let Ok(コンパイル結果) = 高さ場アセットをコンパイルする(&地形の世界のソース一覧()) else {
        panic!("地形の世界の高さ場を焼けなかった");
    };
    let Ok(高さ場) = 実行時形式から高さ場を読む(&コンパイル結果.実行時バイト列) else {
        panic!("焼いた高さ場を実行時形式から復元できなかった");
    };
    let 世界の外 = 大域ワールド位置::生成する(大域メートル::生成する(1_000.0), 大域メートル::生成する(0.0), 大域メートル::生成する(0.0));
    assert!(高さ場.大域の水平位置から地表高さを求める(世界の外).is_err());
}
