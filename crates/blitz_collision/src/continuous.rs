//! 連続衝突: 2つの形がそれぞれ平行移動するときの初回接触時刻を答える。
//!
//! 担当するのは、2つの動きを片側の掃引へ写す還元と、その還元を通して既存の掃引の詳細判定を呼ぶ2つの口
//! (動くカプセルどうし・動くカプセルと動く直方体)である。新しい幾何の数学はここに1つも無い。
//! 実際に時刻を解くのは`crate::capsule`と`crate::oriented_box`の掃引である。
//!
//! この段で作らないものが2つある。1つは回転を含む連続衝突であり、回転が入ると2つの動きの差が1つの平行移動に
//! ならないため、この還元がそのまま使えない。剛体が回転の速い物体を持った日に、角速度から接触時刻の下界を刻む
//! 保守的前進の方式で扱う。もう1つは直方体どうしの掃引であり、剛体の要求が立つまで作らない。積み重なりの
//! 安定に要るのは1点の初回接触ではなく面で乗る接触点の集合であり、そちらは実装順10の担当である。
//! どちらも能力の目録には残っている。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断13: 連続衝突と接触点集合を能力として最初から見据える」
//!
//! 答えの向き。返す接触の単位法線は、静止させた側の表面から掃引する側の軸へ向かう向きである。対のどちらを
//! 静止させる側に選ぶかで符号が反転するため、受け取る側は自分がどちらを静止させたかを知っている必要がある。
//! 接触の時刻と接触の位置は選び方に依らない。

