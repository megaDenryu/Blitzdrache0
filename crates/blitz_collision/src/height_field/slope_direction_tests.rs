//! 傾きから導く向きの反証。法線が単位長で天頂側を向くこと、法線が2方向の接線と直交すること、
//! 平らな面では法線が天頂を向き接線が水平になること、単精度でも単位方向へ狭まることを見る。

#![allow(clippy::unwrap_used)]

use blitz_math::ワールド;

use super::{地表の傾き, 地表の単位向き};

const 許容差: f64 = 1.0e-12;

fn 内積(甲: &地表の単位向き<f64>, 乙: &地表の単位向き<f64>) -> f64 {
    甲.東成分() * 乙.東成分() + 甲.天頂成分() * 乙.天頂成分() + 甲.南成分() * 乙.南成分()
}

#[test]
fn 法線は単位長で天頂側を向く() {
    let 法線 = 地表の傾き::生成する(0.4_f64, -0.25).上向きの単位法線();
    assert!((内積(&法線, &法線) - 1.0).abs() < 許容差, "法線の長さが1でない");
    assert!(法線.天頂成分() > 0.0, "法線が下を向いている");
    assert!(法線.東成分() < 0.0, "東へ上る面の法線は西側へ倒れる");
    assert!(法線.南成分() > 0.0, "南へ下る面の法線は南側へ倒れる");
}

#[test]
fn 法線は東と南の2方向の接線と直交する() {
    let 傾き = 地表の傾き::生成する(0.4_f64, -0.25);
    let 法線 = 傾き.上向きの単位法線();
    for 接線 in [傾き.東向きの単位接線(), 傾き.南向きの単位接線()] {
        assert!(内積(&法線, &接線).abs() < 許容差, "法線と接線が直交しない");
    }
}

#[test]
fn 平らな面の法線は天頂を向き接線は水平である() {
    let 傾き = 地表の傾き::生成する(0.0_f64, 0.0);
    let 法線 = 傾き.上向きの単位法線().方向へ狭める::<ワールド>().unwrap();
    assert_eq!((法線.x(), 法線.y(), 法線.z()), (0.0, 1.0, 0.0));
    let 東の接線 = 傾き.東向きの単位接線().方向へ狭める::<ワールド>().unwrap();
    assert_eq!((東の接線.x(), 東の接線.y(), 東の接線.z()), (1.0, 0.0, 0.0));
    let 南の接線 = 傾き.南向きの単位接線().方向へ狭める::<ワールド>().unwrap();
    assert_eq!((南の接線.x(), 南の接線.y(), 南の接線.z()), (0.0, 0.0, 1.0));
}

// 東へ45度上る面の接線は、東成分と天頂成分が等しく、どちらも2分の1の平方根になる。
#[test]
fn 東の接線は傾きの分だけ持ち上がる() {
    let 接線 = 地表の傾き::生成する(1.0_f64, 0.0).東向きの単位接線();
    let 半分の平方根 = 0.5_f64.sqrt();
    assert!((接線.東成分() - 半分の平方根).abs() < 許容差);
    assert!((接線.天頂成分() - 半分の平方根).abs() < 許容差);
    assert_eq!(接線.南成分(), 0.0);
}

// 単精度でも狭めが通ること自体が単位長の反証になる。`方向`の生成が長さ1から離れた入力を型付きエラーで拒むためである。
#[test]
fn 単精度の法線も単位方向へ狭まる() {
    let 法線 = 地表の傾き::生成する(1.7_f32, 0.9).上向きの単位法線().方向へ狭める::<ワールド>().unwrap();
    assert!(法線.y() > 0.0, "法線が下を向いている");
}
