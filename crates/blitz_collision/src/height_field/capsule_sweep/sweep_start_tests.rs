//! 掃引の始まりで既に地表へ触れている場合の反証。半径ちょうどの高さから面へ向かう掃引と、半径より内側へ入った
//! 掃引と、軸そのものが地表を貫いた掃引は動けた割合0で返り、接触の法線は最も近い特徴から導く。
//! 線分の問い合わせが「始点が地表の下なら交差時刻0」とした設計と同じ考えである。
//!
//! 接触は面へ向かう掃引だけが持つ。半径ちょうどの高さを面に沿って滑る掃引と、食い込んだ状態から面を離れる掃引は
//! 始まりの接触を持たず、触れないまま変位の全体を動ける。零の変位は「今触れているか」の問いとして働き、
//! 始まりの接触をそのまま返す。

#![allow(clippy::unwrap_used)]

use super::sweep_query_fixture::{
    カプセルを作る, 位置, 変位, 平らな地形を作る, 掃引の接触を求める, 接触を取り出す
};
use super::{カプセルが地表に最初に触れる点, 地表に触れた特徴, 掃引の走査が調べた範囲};

// 下端の球の中心が地表からちょうど半径だけ離れた高さで面へ向かって動く掃引は、始まりの時点で地表へ触れている。
// 動けた割合は0であり、接触位置は真下の地表である。
#[test]
fn 半径ちょうどの高さから面へ向かう掃引は始まりで触れている() {
    let 地形 = 平らな地形を作る(5);
    let カプセル = カプセルを作る(位置(1.5, 0.5, 1.5), 位置(1.5, 1.5, 1.5), 0.5, 変位(1.0, -1.0, 0.0));
    let 結果 = 掃引の接触を求める(&地形, 1.0, &カプセル);
    assert_eq!(結果.調べた範囲(), 掃引の走査が調べた範囲::覆いの升目をすべて調べた);
    let 接触 = 接触を取り出す(結果);
    assert_eq!(接触.動けた割合().値(), 0.0);
    assert_eq!(接触.接触位置(), 位置(1.5, 0.0, 1.5));
    assert_eq!(接触.接触の単位法線().天頂成分(), 1.0);
    assert_eq!(接触.触れた特徴(), 地表に触れた特徴::三角形の面);
}

// 反証: 始まりで半径以内に居る候補を向きを問わず割合0で返すと、面に隙間なく触れたまま面に沿う掃引が一歩も動けない。
// 水平に動く掃引は、通り道の升目の辺と頂点をかすめるだけであり、どこにも触れずに変位の全体を動ける。
#[test]
fn 半径ちょうどの高さを滑る掃引は触れずに変位の全体を動ける() {
    let 地形 = 平らな地形を作る(5);
    let カプセル = カプセルを作る(位置(1.5, 0.5, 1.5), 位置(1.5, 1.5, 1.5), 0.5, 変位(1.0, 0.0, 0.0));
    let 結果 = 掃引の接触を求める(&地形, 1.0, &カプセル);
    assert_eq!(結果.調べた範囲(), 掃引の走査が調べた範囲::覆いの升目をすべて調べた);
    assert_eq!(結果.最初に触れる点(), カプセルが地表に最初に触れる点::地表に触れない);
}

// 下端の球が地表へ0.3メートル食い込んだ状態から面へ向かう掃引は、動けた割合0で接触を返す。
// 最も近い特徴は真下の面であり、法線は上向きである。
#[test]
fn 地表へ食い込んだ状態から面へ向かう掃引は一歩も動けない() {
    let 地形 = 平らな地形を作る(4);
    let カプセル = カプセルを作る(位置(1.5, 0.2, 1.5), 位置(1.5, 1.2, 1.5), 0.5, 変位(0.0, -1.0, 0.0));
    let 接触 = 接触を取り出す(掃引の接触を求める(&地形, 1.0, &カプセル));
    assert_eq!(接触.動けた割合().値(), 0.0);
    assert_eq!(接触.接触位置(), 位置(1.5, 0.0, 1.5));
    assert_eq!(接触.接触の単位法線().天頂成分(), 1.0);
    assert_eq!(接触.触れた特徴(), 地表に触れた特徴::三角形の面);
}

// 反証: 食い込んだ状態から離れる掃引を割合0で止めると、食い込みから抜け出せない。離れる側の根(隔たりが半径を
// 越えて広がる時刻)も接触ではないため、変位の全体を動ける。
#[test]
fn 地表へ食い込んだ状態から離れる掃引は変位の全体を動ける() {
    let 地形 = 平らな地形を作る(4);
    let カプセル = カプセルを作る(位置(1.5, 0.2, 1.5), 位置(1.5, 1.2, 1.5), 0.5, 変位(0.0, 1.0, 0.0));
    let 結果 = 掃引の接触を求める(&地形, 1.0, &カプセル);
    assert_eq!(結果.調べた範囲(), 掃引の走査が調べた範囲::覆いの升目をすべて調べた);
    assert_eq!(結果.最初に触れる点(), カプセルが地表に最初に触れる点::地表に触れない);
}

#[test]
fn 零の変位の掃引は食い込んでいる事実を返す() {
    let 地形 = 平らな地形を作る(4);
    let カプセル = カプセルを作る(位置(1.5, 0.2, 1.5), 位置(1.5, 1.2, 1.5), 0.5, 変位(0.0, 0.0, 0.0));
    let 接触 = 接触を取り出す(掃引の接触を求める(&地形, 1.0, &カプセル));
    assert_eq!(接触.動けた割合().値(), 0.0);
    assert_eq!(接触.接触位置(), 位置(1.5, 0.0, 1.5));
}

// 軸そのものが地表を貫いているカプセルは、面までの隔たりも辺と頂点までの隔たりも半径より大きくなりうる。
// 貫きの判定が別に要るのはそのためであり、貫いた場合の隔たりは0で、接触位置は軸が面を貫いた点である。
#[test]
