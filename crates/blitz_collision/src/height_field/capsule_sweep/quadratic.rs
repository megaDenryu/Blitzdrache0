//! 掃引の2次方程式: 掃引で動けた割合について、接触の条件を2次までの式で表したものである。
//! どの特徴の接触もこの1つの形へ帰着する。面と軸の端点の組は2次の係数が0になり1次式として解ける。
//!
//! 根は判別式の平方根から直接求める。数値の刻み探索も二分法も反復法も使わないのは、同じ入力が必ずビット単位で
//! 同じ根を返すためである(`_doc/設計/世界の形と衝突基盤.md`「判断14: 決定性の維持」)。
//!
//! 誤差について。線分と高さ場のときのような厳密な上界は導いていない。ここに書くのは、誤差がどの演算で入るかと、
//! 入った誤差が貫通として現れうるかである。数値を偽らないため、「厳密」とも「必ず取り逃さない」とも書かない。
//!
//! 誤差が入るのは4箇所である。(1)係数を組む内積と外積。近い2つの量の差で桁落ちする。(2)判別式の減算。
//! 2つの根が近い(カプセルが特徴をかすめる)ほど大きな2項の差になり、相対誤差が育つ。(3)平方根。
//! 正しく丸められるため半ULPで済む。(4)根を求める割り算。以上から、根の相対誤差はふつう数ULPだが、
//! 判別式が0に近いところでは判別式の相対誤差の平方根まで育つ。
//!
//! 接触の時刻がわずかに遅れると、そのぶんカプセルが地表へ食い込む。食い込む深さは、遅れた時間に掃引の速さを
//! 掛けた量である。判別式が0に近い場合はかすめる接触であり、深さは接触の隔たりの変化が遅い向きに現れるため
//! さらに小さい。食い込んだ状態は次の刻みで拾い直される。次の刻みの始まりで隔たりが半径以下になっており、
//! 「掃引の始まりから触れている」として動けた割合0と最も近い特徴の法線が返るからである。したがって
//! 遅れは薄い地形をすり抜ける形の貫通にはならない。時刻がわずかに早まった場合は、まだ届いていない位置で
//! 接触を返す。隔たりは半径をわずかに上回るだけであり、位置と法線はその時刻の幾何と整合したままである。
//! 根を求め直した時刻でもう一度その特徴との最近接を組み直すためである。
//!
//! 2つの根が近いときの桁落ちを避けるため、和の側の根を先に求めて積の関係から他方を求める形にする。

pub(super) struct 掃引の2次方程式 {
    二次の係数: f64,
    一次の係数: f64,
    定数項: f64,
}

impl 掃引の2次方程式 {
    pub(super) fn 生成する(二次の係数: f64, 一次の係数: f64, 定数項: f64) -> Self {
        Self {
            二次の係数,
            一次の係数,
            定数項,
        }
    }

    /// 実数の根を小さい順に並べる。根を持たない場合と、係数がすべて0で恒等式になる場合は空である。
    /// 恒等式を根なしとして扱うのは、その特徴では接触の時刻が定まらず、他の特徴が同じ接触を答えるためである。
    pub(super) fn 根を小さい順に並べる(&self) -> impl Iterator<Item = f64> {
        self.根の対を求める().into_iter().flatten()
    }

    fn 根の対を求める(&self) -> [Option<f64>; 2] {
        if self.二次の係数 == 0.0 {
            if self.一次の係数 == 0.0 {
                return [None, None];
            }
            return [Some(-self.定数項 / self.一次の係数), None];
        }
        let 判別式 = self.一次の係数 * self.一次の係数 - 4.0 * self.二次の係数 * self.定数項;
        if !判別式.is_finite() || 判別式 < 0.0 {
            return [None, None];
        }
        let 和の側 = -0.5 * (self.一次の係数 + self.一次の係数.signum() * 判別式.sqrt());
        let 片方 = 和の側 / self.二次の係数;
        let 他方 = if 和の側 == 0.0 { 片方 } else { self.定数項 / 和の側 };
        if 片方 <= 他方 {
            [Some(片方), Some(他方)]
        } else {
            [Some(他方), Some(片方)]
        }
    }
}
