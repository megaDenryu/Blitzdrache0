//! 三角形の辺の内側と軸の内側の接触。ねじれの位置にある2直線どうしが半径だけ離れて並ぶ時刻を解く。
//!
//! 2直線の隔たりは、両方に垂直な向き(2つの変位の外積)へ射影した長さである。射影は時刻の1次式であるから、
//! 隔たりが半径に等しくなる時刻も1次で決まる。2乗した形で解くのは、カプセルが辺のどちら側から来ても
//! 同じ1つの式で扱うためである。2つの直線が平行なとき外積は零になり、隔たりが定まらないためこの候補を数えない。
//! 平行な場合の最も早い接触は、軸の端か辺の端すなわち三角形の頂点の候補が同じ時刻で答える。
//!
//! 直線は辺と軸より長いため、根の時刻で2つの最近接点がそれぞれ辺と軸の内側に収まることを確かめる。

use super::axis_end::軸の端;
use super::contact_candidate::軸と特徴の最近接;
use super::contact_solver::カプセルと三角形の接触の求解;
use super::error::カプセルの掃引の問い合わせエラー;
use super::line_pair::軸と辺の最近接の媒介変数;
use super::quadratic::掃引の2次方程式;

impl カプセルと三角形の接触の求解<'_> {
    pub(super) fn 辺と軸の内側の方程式を組む(&self, 辺の並びの位置: usize) -> Option<掃引の2次方程式> {
        let 両方に垂直な向き = self.軸の変位().外積(self.辺の変位(辺の並びの位置));
        let 向きの長さの二乗 = 両方に垂直な向き.長さの二乗();
        if 向きの長さの二乗 <= 0.0 {
            return None;
        }
        let 始まりの射影 = self
            .頂点から時刻の軸の端への変位(辺の並びの位置, 軸の端::始点の側, 0.0)
            .内積(両方に垂直な向き);
        let 射影の速度 = self.掃引の変位().内積(両方に垂直な向き);
        Some(掃引の2次方程式::生成する(
            射影の速度 * 射影の速度,
            2.0 * 始まりの射影 * 射影の速度,
            始まりの射影 * 始まりの射影 - self.半径の二乗() * 向きの長さの二乗,
        ))
    }

    // 時刻での、辺の直線と軸の直線の最近接。どちらかの最近接点がその範囲の外にあるなら`None`を返す。
    pub(super) fn 辺と軸の内側の最近接を求める(
        &self,
        辺の並びの位置: usize,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, カプセルの掃引の問い合わせエラー> {
        let 軸 = self.軸の変位();
        let 辺 = self.辺の変位(辺の並びの位置);
        let 辺の始点から軸の始点へ = self.頂点から時刻の軸の端への変位(辺の並びの位置, 軸の端::始点の側, 時刻);
        let Some(媒介変数) = 軸と辺の最近接の媒介変数::求める(軸, 辺, 辺の始点から軸の始点へ) else {
            return Ok(None);
        };
        let 接触点から軸へ = 辺の始点から軸の始点へ
            .加える(軸.実数倍する(媒介変数.軸の比()))
            .引く(辺.実数倍する(媒介変数.辺の比()));
        Ok(Some(self.辺に触れた最近接を組む(
            辺の並びの位置,
            媒介変数.辺の比(),
            接触点から軸へ,
        )?))
    }
}
