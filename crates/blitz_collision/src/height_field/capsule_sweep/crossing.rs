//! 掃引の始まりで、カプセルの軸そのものが三角形を貫いているかの判定。貫いていれば隔たりは0である。
//!
//! この判定が別に要るのは、特徴ごとの最近接がどれも面か辺か頂点までの隔たりを答えるためである。軸が面を
//! 貫いていると、軸の両端はどちらも面から離れており、辺と頂点までの隔たりも正のまま残る。したがって
//! 特徴の最小だけでは「隔たり0」に達しない。三角形を突き抜けるほど深く沈んだカプセルを、
//! 触れていないと答えないためにこの判定を置く。
//!
//! 貫いた場合の接触の単位法線は、最も近い特徴から導けない。軸の両側に三角形があり、どちらへ押し戻すのが
//! 近いかがこの層では決まらないためである。地表の上向きの単位法線を返し、その旨をここに記す。

use super::axis_end::軸の端;
use super::contact_candidate::軸と特徴の最近接;
use super::contact_place::触れた場所;
use super::contact_solver::カプセルと三角形の接触の求解;
use super::error::カプセルの掃引の問い合わせエラー;
use super::feature::地表に触れた特徴;

impl カプセルと三角形の接触の求解<'_> {
    pub(super) fn 軸が三角形を貫く場所を求める(
        &self,
    ) -> Result<Option<軸と特徴の最近接>, カプセルの掃引の問い合わせエラー> {
        let 法線 = self.上向きの法線の変位();
        let 始点の隔たり = self.頂点から時刻の軸の端への変位(0, 軸の端::始点の側, 0.0).内積(法線);
        let 終点の隔たり = self.頂点から時刻の軸の端への変位(0, 軸の端::終点の側, 0.0).内積(法線);
        if 始点の隔たり * 終点の隔たり > 0.0 {
            return Ok(None);
        }
        let 貫く比 = 平面を横切る比を求める(始点の隔たり, 終点の隔たり);
        let 貫いた位置 = self
            .軸の端の位置(軸の端::始点の側)
            .変位だけ進んだ位置を求める(self.軸の変位().実数倍する(貫く比))?;
        if !self.三角形().面の上の点が内側にあるか(貫いた位置) {
            return Ok(None);
        }
        Ok(Some(軸と特徴の最近接::生成する(
            0.0,
            触れた場所::生成する(貫いた位置, self.三角形().上向きの単位法線(), 地表に触れた特徴::三角形の面),
        )))
    }
}

// 軸の上で平面を横切る比。両端の隔たりが同じ値になるのは軸が平面に乗っている場合であり、
// そのときは軸の始点を代表の点として調べる。
fn 平面を横切る比を求める(始点の隔たり: f64, 終点の隔たり: f64) -> f64 {
    let 差 = 始点の隔たり - 終点の隔たり;
    if 差 == 0.0 {
        return 0.0;
    }
    (始点の隔たり / 差).clamp(0.0, 1.0)
}
