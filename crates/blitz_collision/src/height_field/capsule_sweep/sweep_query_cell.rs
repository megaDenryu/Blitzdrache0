//! 升目の中の三角形1つについて、カプセルの掃引の接触を求める工程。走査から呼ばれ、受け取るのはカプセルと
//! 升目の添字と四隅の高さと2つの三角形のどちらかであり、返すのは三角形1つを調べた答えである。
//!
//! 掃引の始まりで既に半径以内に居てそこへ向かう特徴があるかを先に調べる。あれば動ける割合は0であり、
//! そのときの接触の法線は最も近い特徴から導く。線分の問い合わせが「始点が地表の下なら交差時刻0」とした
//! 設計と同じ考えである。面から離れる変位と平行な変位では始まりの候補を数えない(`contact_direction.rs`)。
//! 参照: `crates/blitz_collision/src/height_field/cell_segment_intersection.rs`

use super::super::cell_corner_heights::升目の四隅の高さ;
use super::super::cell_index::升目の格子添字;
use super::super::corner_source::升目の四隅の高さの供給元;
use super::super::triangle::升目の三角形;
use super::capsule::高さ場を掃引するカプセル;
use super::contact::掃引したカプセルの地表への接触;
use super::contact_solver::カプセルと三角形の接触の求解;
use super::error::カプセルの掃引の問い合わせエラー;
use super::surface_triangle::升目の地表の三角形;
use super::sweep_query::高さ場のカプセルの掃引の問い合わせ;
use super::triangle_answer::三角形の中の接触;
use crate::solver::掃引で動けた割合;

impl<供給元: 升目の四隅の高さの供給元> 高さ場のカプセルの掃引の問い合わせ<'_, 供給元> {
    pub(super) fn 三角形1つの接触を求める(
        &self,
        カプセル: &高さ場を掃引するカプセル,
        添字: 升目の格子添字,
        四隅: &升目の四隅の高さ<f64>,
        三角形: 升目の三角形,
    ) -> Result<三角形の中の接触, カプセルの掃引の問い合わせエラー> {
        let 地表の三角形 = 升目の地表の三角形::生成する(添字, 四隅, self.升目の一辺(), 三角形)?;
        let 求解 = カプセルと三角形の接触の求解::生成する(カプセル, &地表の三角形);
        if let Some(最近接) = 求解.掃引の始まりで触れている最も近い特徴を求める()? {
            return Ok(三角形の中の接触::掃引の始まりから触れている {
                隔たりの二乗: 最近接.隔たりの二乗(),
                接触: 掃引したカプセルの地表への接触::生成する(
                    掃引で動けた割合::一歩も動けなかった(),
                    最近接.場所(),
                    添字,
                    三角形,
                ),
            });
        }
        let Some(触れ始める) = 求解.掃引の途中で最初に触れる接触を求める()? else {
            return Ok(三角形の中の接触::どこでも触れない);
        };
        Ok(三角形の中の接触::掃引の途中で触れ始める {
            動けた割合: 触れ始める.動けた割合(),
            接触: 掃引したカプセルの地表への接触::生成する(触れ始める.動けた割合(), 触れ始める.場所(), 添字, 三角形),
        })
    }
}
