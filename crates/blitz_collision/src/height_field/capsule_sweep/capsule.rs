//! 高さ場を掃引するカプセル: 両端が半球になった円柱を、指定した変位だけ平行移動させる掃引そのものである。
//! 軸の両端と半径が形を、掃引の変位が動きを表す。形と動きを1つの型にまとめるのは、問い合わせが答えるのが
//! 「この形をこの変位だけ動かすとどこまで動けるか」という1つの問いであり、片方だけでは問いにならないためである。
//!
//! 半径が正の有限であることをこの型が守る。軸の両端と掃引の変位の有限性はそれぞれの型が守る。
//! 位置の絶対値には上限を課さない。四隅の高さへ課した2の24乗メートルの上限は、隣り合う升目が共有辺の上で
//! 返す高さの差の上界を導くための条件であり、カプセルの位置はその導出に現れないためである。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断7: 高さ場の物理は最詳細段の三角形化と一致させる」

use super::super::grid_origin_displacement::高さ場の中の変位;
use super::super::grid_origin_position::高さ場の格子原点からの位置;
use super::error::カプセルの掃引の問い合わせエラー;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 高さ場を掃引するカプセル {
    軸の始点: 高さ場の格子原点からの位置,
    軸の終点: 高さ場の格子原点からの位置,
    半径のメートル: f64,
    掃引の変位: 高さ場の中の変位,
}

impl 高さ場を掃引するカプセル {
    pub fn 生成する(
        軸の始点: 高さ場の格子原点からの位置,
        軸の終点: 高さ場の格子原点からの位置,
        半径のメートル: f64,
        掃引の変位: 高さ場の中の変位,
    ) -> Result<Self, カプセルの掃引の問い合わせエラー> {
        if !半径のメートル.is_finite() || 半径のメートル <= 0.0 {
            return Err(カプセルの掃引の問い合わせエラー::カプセルの半径が正の有限値でない);
        }
        Ok(Self {
            軸の始点,
            軸の終点,
            半径のメートル,
            掃引の変位,
        })
    }

    pub fn 軸の始点(&self) -> 高さ場の格子原点からの位置 {
        self.軸の始点
    }

    pub fn 軸の終点(&self) -> 高さ場の格子原点からの位置 {
        self.軸の終点
    }

    pub fn 半径のメートル(&self) -> f64 {
        self.半径のメートル
    }

    pub fn 掃引の変位(&self) -> 高さ場の中の変位 {
        self.掃引の変位
    }

    /// 軸の始点から終点へ向かう変位。長さ0の軸(球)も許すため、この変位は零になりうる。
    pub(super) fn 軸の変位を求める(&self) -> 高さ場の中の変位 {
        self.軸の始点.終点までの変位を求める(self.軸の終点)
    }

    /// 掃引の始まりの姿勢での軸の2つの端点。並びは始点・終点であり、走査はこの順に候補を数える。
    pub(super) fn 軸の端点を並べる(&self) -> [高さ場の格子原点からの位置; 2] {
        [self.軸の始点, self.軸の終点]
    }
}
