//! 高さ場を掃引するカプセル: 両端が半球になった円柱を、指定した変位だけ平行移動させる掃引そのものである。
//! 軸の両端と半径が形を、掃引の変位が動きを表す。形と動きを1つの型にまとめるのは、問い合わせが答えるのが
//! 「この形をこの変位だけ動かすとどこまで動けるか」という1つの問いであり、片方だけでは問いにならないためである。
//!
//! 半径が正の有限であり絶対値の下限と上限の間に収まることをこの型が守る。軸の両端と掃引の変位は、有限性と
//! 同じ上限をそれぞれの型が守る。上限を課すのは、掃引の2次方程式の係数と判別式が桁あふれしないことを保証する
//! ためである。上限とその算術は `crates/blitz_collision/src/height_field/length_limit.rs` にある。
//! 下限を課すのは、求解が作る半径の二乗が非正規化数へ落ちて0へ潰れないことを保証するためである。下限とその
//! 算術は `crates/blitz_collision/src/height_field/capsule_sweep/radius_lower_limit.rs` にある。

use super::super::grid_origin_displacement::高さ場の中の変位;
use super::super::grid_origin_position::高さ場の格子原点からの位置;
use super::super::length_limit::高さ場の問い合わせが受け付ける長さの絶対値の上限メートル;
use super::error::カプセルの掃引の問い合わせエラー;
use super::radius_lower_limit::高さ場を掃引するカプセルの半径の下限メートル;

/// 高さ場を掃引するカプセル。両端が半球になった円柱の形と、それを動かす変位を1つにまとめて持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 高さ場を掃引するカプセル {
    軸の始点: 高さ場の格子原点からの位置,
    軸の終点: 高さ場の格子原点からの位置,
    半径のメートル: f64,
    掃引の変位: 高さ場の中の変位,
}

impl 高さ場を掃引するカプセル {
    /// 半径が正の有限であり下限と上限の間に収まることを確かめて作る。軸の両端と掃引の変位は同じ上限をそれぞれの型が守る。
    pub fn 生成する(
        軸の始点: 高さ場の格子原点からの位置,
        軸の終点: 高さ場の格子原点からの位置,
        半径のメートル: f64,
        掃引の変位: 高さ場の中の変位,
    ) -> Result<Self, カプセルの掃引の問い合わせエラー> {
        if !半径のメートル.is_finite() || 半径のメートル <= 0.0 {
            return Err(カプセルの掃引の問い合わせエラー::カプセルの半径が正の有限値でない);
        }
        if 半径のメートル < 高さ場を掃引するカプセルの半径の下限メートル {
            return Err(カプセルの掃引の問い合わせエラー::カプセルの半径が下限を下回っている);
        }
        if 半径のメートル > 高さ場の問い合わせが受け付ける長さの絶対値の上限メートル {
            return Err(カプセルの掃引の問い合わせエラー::カプセルの半径が上限を越えている);
        }
        Ok(Self {
            軸の始点,
            軸の終点,
            半径のメートル,
            掃引の変位,
        })
    }

    /// 掃引の始まりの姿勢での軸の始点。
    pub fn 軸の始点(&self) -> 高さ場の格子原点からの位置 {
        self.軸の始点
    }

    /// 掃引の始まりの姿勢での軸の終点。
    pub fn 軸の終点(&self) -> 高さ場の格子原点からの位置 {
        self.軸の終点
    }

    /// 軸から測ったカプセルの半径であるメートル。
    pub fn 半径のメートル(&self) -> f64 {
        self.半径のメートル
    }

    /// カプセル全体を動かそうとする変位。
    pub fn 掃引の変位(&self) -> 高さ場の中の変位 {
        self.掃引の変位
    }

    // 軸の始点から終点へ向かう変位。長さ0の軸(球)も許すため、この変位は零になりうる。
    pub(super) fn 軸の変位を求める(&self) -> 高さ場の中の変位 {
        self.軸の始点.終点までの変位を求める(self.軸の終点)
    }

    // 掃引の始まりの姿勢での軸の2つの端点。並びは始点・終点であり、走査はこの順に候補を数える。
    pub(super) fn 軸の端点を並べる(&self) -> [高さ場の格子原点からの位置; 2] {
        [self.軸の始点, self.軸の終点]
    }
}
