//! 面以外の特徴で触れる掃引と、斜面へ斜めに進む掃引の反証。
//!
//! 尾根と峰を使うのは、升目の境界に立つ凸の角へカプセルの球面が当たる場合を作るためである。凸の角では、
//! 面までの隔たりよりも辺と頂点までの隔たりのほうが先に半径へ達する。
//! 斜面の期待値だけは厳密な値で書けない。水平でない平面の単位法線は2進の有限小数にならないためである
//! (勾配が4分の3の面の単位法線は5分の3と5分の4であり、どちらも2進では循環する)。
//! そのため斜面の反証は解析解との差が10のマイナス12乗より小さいことを見る。

#![allow(clippy::unwrap_used)]

use super::super::cell_corner::升目の隅;
use super::super::升目の三角形;
use super::sweep_query_fixture::{
    カプセルを作る, 中央が高い地形を作る, 位置, 変位, 尾根がある地形を作る, 掃引の接触を求める, 接触を取り出す, 東へ一定の勾配の地形を作る,
};
use super::地表に触れた特徴;

/// 稜線の真上から落ちるカプセルは、下端の球が稜線から半径だけ離れた高さで止まる。稜線は高さ1メートルであり
/// 半径は0.5メートルであるから、球の中心が高さ1.5メートルに達した時点、すなわち3メートルから1.5メートル
/// 落ちた時点である。動けた割合は1.5割る2の0.75である。
#[test]
fn 稜線へ落ちるカプセルは辺の特徴で触れる() {
    let カプセル = カプセルを作る(位置(1.0, 3.0, 0.5), 位置(1.0, 4.0, 0.5), 0.5, 変位(0.0, -2.0, 0.0));
    let 接触 = 接触を取り出す(掃引の接触を求める(&尾根がある地形を作る(), 1.0, &カプセル));
    assert_eq!(接触.動けた割合().値(), 0.75);
    assert_eq!(接触.接触位置(), 位置(1.0, 1.0, 0.5));
    assert_eq!(接触.接触の単位法線().天頂成分(), 1.0);
    assert_eq!(
        接触.触れた特徴(),
        地表に触れた特徴::三角形の辺 {
            始まりの隅: 升目の隅::手前右,
            終わりの隅: 升目の隅::奥右
        }
    );
    assert_eq!(接触.升目の添字().東添字(), 0);
    assert_eq!(接触.三角形(), 升目の三角形::手前側);
}

/// 峰の真上から落ちるカプセルは、下端の球が峰の格子点から半径だけ離れた高さで止まる。落ちる量は稜線の場合と
/// 同じであり、触れる特徴だけが頂点になる。
#[test]
fn 峰へ落ちるカプセルは頂点の特徴で触れる() {
    let カプセル = カプセルを作る(位置(1.0, 3.0, 1.0), 位置(1.0, 4.0, 1.0), 0.5, 変位(0.0, -2.0, 0.0));
    let 接触 = 接触を取り出す(掃引の接触を求める(&中央が高い地形を作る(), 1.0, &カプセル));
    assert_eq!(接触.動けた割合().値(), 0.75);
    assert_eq!(接触.接触位置(), 位置(1.0, 1.0, 1.0));
    assert_eq!(接触.接触の単位法線().天頂成分(), 1.0);
    assert_eq!(接触.触れた特徴(), 地表に触れた特徴::三角形の頂点(升目の隅::奥右));
    assert_eq!(接触.升目の添字().東添字(), 0);
    assert_eq!(接触.三角形(), 升目の三角形::奥側);
}

/// 東へ1メートルにつき0.75メートル上がる斜面へ、東へ1メートル・下へ1メートル進む掃引をかける。
/// 面の単位法線は東成分が-0.6・天頂成分が0.8であるから、下端の球の中心と面の隔たりは始まりで1.8メートル、
/// 1進むごとに1.4メートル縮む。半径0.5メートルに達するのは1.3割る1.4を進んだ時点である。
#[test]
fn 斜面へ斜めに進むカプセルは面の特徴で触れる() {
    let 地形 = 東へ一定の勾配の地形を作る(4, 0.75);
    let カプセル = カプセルを作る(位置(1.0, 3.0, 1.5), 位置(1.0, 4.0, 1.5), 0.5, 変位(1.0, -1.0, 0.0));
    let 接触 = 接触を取り出す(掃引の接触を求める(&地形, 1.0, &カプセル));
    let 期待する割合 = 1.3 / 1.4;
    assert!((接触.動けた割合().値() - 期待する割合).abs() < 1.0e-12);
    assert!((接触.接触位置().東のメートル() - (1.0 + 期待する割合 + 0.3)).abs() < 1.0e-12);
    assert!((接触.接触位置().天頂のメートル() - (3.0 - 期待する割合 - 0.4)).abs() < 1.0e-12);
    assert!((接触.接触位置().南のメートル() - 1.5).abs() < 1.0e-12);
    assert!((接触.接触の単位法線().東成分() + 0.6).abs() < 1.0e-12);
    assert!((接触.接触の単位法線().天頂成分() - 0.8).abs() < 1.0e-12);
    assert_eq!(接触.触れた特徴(), 地表に触れた特徴::三角形の面);
    assert_eq!(接触.升目の添字().東添字(), 2);
    assert_eq!(接触.升目の添字().南添字(), 1);
    assert_eq!(接触.三角形(), 升目の三角形::奥側);
}
