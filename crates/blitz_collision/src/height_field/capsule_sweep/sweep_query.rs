//! 高さ場のカプセルの掃引の問い合わせ: カプセルを変位の分だけ動かそうとしたとき、地表に触れるまでに
//! どこまで動けるかを求める操作サービス。四隅の高さの供給元と升目の一辺をコンストラクタで受け取って
//! 保持するため、問い合わせの署名に高さの並びも格子の刻みも現れない。
//!
//! 1回の問い合わせでヒープを確保しない。走査が持つのは覆いの矩形と、これまでの最小の接触だけであり、
//! 覆いの升目を貯めずに1つずつ調べて捨てる。
//!
//! 覆いの中に四隅を答えられない升目が1つでもあれば、見つけた接触を捨てて打ち切りの側で答える。
//! 覆いは面であり升目を接触の時刻の順に並べられないため、答えられない升目にもっと早い接触がありうるからである。
//! 線分の走査が「答えられない升目に達した時点で止める」ことで同じ確定性を得ているのと、至る道が違う。

use super::super::cell_edge::升目の一辺;
use super::super::corner_source::升目の四隅の高さの供給元;
use super::super::triangle::升目の三角形;
use super::capsule::高さ場を掃引するカプセル;
use super::covering::掃引の水平の覆い;
use super::error::カプセルの掃引の問い合わせエラー;
use super::sweep_result::カプセルの掃引と高さ場の接触の結果;
use super::triangle_answer::三角形の中の接触;
use crate::solver::最も小さい量の候補だけを覚える器;

/// 高さ場のカプセルの掃引の問い合わせ。四隅の高さの供給元と升目の一辺を保持し、掃引の接触を答える操作サービスである。
pub struct 高さ場のカプセルの掃引の問い合わせ<'供給元, 供給元> {
    四隅の供給元: &'供給元 供給元,
    升目の一辺: 升目の一辺<f64>,
}

impl<'供給元, 供給元: 升目の四隅の高さの供給元> 高さ場のカプセルの掃引の問い合わせ<'供給元, 供給元> {
    /// 四隅の高さの供給元と升目の一辺を受け取って作る。
    pub fn 生成する(四隅の供給元: &'供給元 供給元, 升目の一辺: 升目の一辺<f64>) -> Self {
        Self {
            四隅の供給元, 升目の一辺
        }
    }

    pub(super) fn 升目の一辺(&self) -> 升目の一辺<f64> {
        self.升目の一辺
    }

    /// カプセルが地表に最初に触れる点を求める。触れない場合と、調べられない升目があって打ち切った場合を
    /// 結果の2つの軸で区別する。
    pub fn カプセルが地表に最初に触れる点を求める(
        &self,
        カプセル: &高さ場を掃引するカプセル,
    ) -> Result<カプセルの掃引と高さ場の接触の結果, カプセルの掃引の問い合わせエラー> {
        let Some(覆い) = 掃引の水平の覆い::カプセルの掃引から求める(カプセル, self.升目の一辺) else {
            return Ok(カプセルの掃引と高さ場の接触の結果::調べられない升目で打ち切った());
        };
        let mut 始まりから触れている接触 = 最も小さい量の候補だけを覚える器::まだ何も無い状態から始める();
        let mut 途中で触れ始める接触 = 最も小さい量の候補だけを覚える器::まだ何も無い状態から始める();
        for 添字 in 覆い.升目を並べる() {
            let Some(四隅) = self.四隅の供給元.升目の四隅の高さを参照する(添字) else {
                return Ok(カプセルの掃引と高さ場の接触の結果::調べられない升目で打ち切った());
            };
            for 三角形 in [升目の三角形::奥側, 升目の三角形::手前側] {
                match self.三角形1つの接触を求める(カプセル, 添字, &四隅, 三角形)? {
                    三角形の中の接触::掃引の始まりから触れている { 隔たりの二乗, 接触 } => {
                        始まりから触れている接触.候補を1つ数える(隔たりの二乗, 接触);
                    }
                    三角形の中の接触::掃引の途中で触れ始める { 動けた割合, 接触 } => {
                        途中で触れ始める接触.候補を1つ数える(動けた割合.値(), 接触);
                    }
                    三角形の中の接触::どこでも触れない => {}
                }
            }
        }
        if let Some(接触) = 始まりから触れている接触.覚えている候補を取り出す() {
            return Ok(カプセルの掃引と高さ場の接触の結果::覆いをすべて調べて接触を見つけた(接触));
        }
        Ok(match 途中で触れ始める接触.覚えている候補を取り出す() {
            Some(接触) => カプセルの掃引と高さ場の接触の結果::覆いをすべて調べて接触を見つけた(接触),
            None => カプセルの掃引と高さ場の接触の結果::覆いをすべて調べて触れなかった(),
        })
    }
}
