//! 平らな地形に対するカプセルの掃引の反証。垂直に落ちる掃引・地表の上を水平に動く掃引・覆いが複数の升目に
//! またがる掃引・覆いが格子の外へはみ出す掃引・同じ入力の2回評価を、手で解いた期待値と突き合わせる。
//!
//! 期待値はどれも2次方程式を手で解いて出す。カプセルの軸は鉛直、地表は水平であるから、球の中心と平面の隔たりが
//! 半径に等しくなる時刻がそのまま答えである。判別式が平方数になる数を選べば、根は倍精度で厳密に表せる。

#![allow(clippy::unwrap_used)]

use super::super::升目の三角形;
use super::sweep_query_fixture::{
    カプセルを作る, 位置, 変位, 平らな地形を作る, 掃引の接触を求める, 接触を取り出す
};
use super::{カプセルが地表に最初に触れる点, 地表に触れた特徴, 掃引の走査が調べた範囲};

// 高さ3メートルの下端を持つ半径0.5メートルのカプセルが、4メートル落ちようとする。下端の球は中心が高さ0.5まで
// 落ちた時点で地表に触れるから、2.5メートル落ちた時点であり、動けた割合は2.5割る4の0.625である。
#[test]
fn 平らな地形へ垂直に落ちるカプセルは半径だけ手前で止まる() {
    let 地形 = 平らな地形を作る(3);
    let カプセル = カプセルを作る(位置(1.0, 3.0, 1.0), 位置(1.0, 4.0, 1.0), 0.5, 変位(0.0, -4.0, 0.0));
    let 結果 = 掃引の接触を求める(&地形, 1.0, &カプセル);
    assert_eq!(結果.調べた範囲(), 掃引の走査が調べた範囲::覆いの升目をすべて調べた);
    let 接触 = 接触を取り出す(結果);
    assert_eq!(接触.動けた割合().値(), 0.625);
    assert_eq!(接触.接触位置(), 位置(1.0, 0.0, 1.0));
    assert_eq!(接触.接触の単位法線().天頂成分(), 1.0);
    assert_eq!(接触.触れた特徴(), 地表に触れた特徴::三角形の面);
    assert_eq!(接触.升目の添字().東添字(), 0);
    assert_eq!(接触.升目の添字().南添字(), 0);
    assert_eq!(接触.三角形(), 升目の三角形::奥側);
}

// 地表から2メートル浮いたまま水平に動くカプセルは、半径0.5メートルでは地表に届かない。
// 覆いの升目をすべて調べ切ったことも見る。触れなかったことと調べ切れなかったことは別の事実だからである。
#[test]
fn 地表の上を水平に動くカプセルは触れないまま覆いを調べ切る() {
    let 地形 = 平らな地形を作る(4);
    let カプセル = カプセルを作る(位置(0.5, 2.0, 0.5), 位置(0.5, 3.0, 0.5), 0.5, 変位(1.0, 0.0, 0.0));
    let 結果 = 掃引の接触を求める(&地形, 1.0, &カプセル);
    assert_eq!(結果.調べた範囲(), 掃引の走査が調べた範囲::覆いの升目をすべて調べた);
    assert_eq!(結果.最初に触れる点(), カプセルが地表に最初に触れる点::地表に触れない);
}

// 東へ3メートル・下へ1メートル動く掃引は、覆いが東に5つの升目へまたがる。下端の球の中心は高さ1メートルから
// 1メートル下がるから、高さ0.5メートルに達するのは半分進んだ時点であり、そこは東2メートルの升目の境目である。
#[test]
fn 覆いが複数の升目にまたがる掃引も最初に触れる升目を答える() {
    let 地形 = 平らな地形を作る(6);
    let カプセル = カプセルを作る(位置(0.5, 1.0, 0.5), 位置(0.5, 2.0, 0.5), 0.5, 変位(3.0, -1.0, 0.0));
    let 接触 = 接触を取り出す(掃引の接触を求める(&地形, 1.0, &カプセル));
    assert_eq!(接触.動けた割合().値(), 0.5);
    assert_eq!(接触.接触位置(), 位置(2.0, 0.0, 0.5));
    assert_eq!(接触.触れた特徴(), 地表に触れた特徴::三角形の面);
    assert_eq!(接触.升目の添字().東添字(), 1);
    assert_eq!(接触.三角形(), 升目の三角形::手前側);
}

// 覆いが格子の広がりの外へはみ出す掃引は、その升目に接触の可能性が残るため、見つけた接触を捨てて打ち切る。
// 覆いは面であり升目を接触の時刻の順に並べられず、はみ出した先にもっと早い接触がありうるからである。
#[test]
fn 覆いが格子の外へはみ出す掃引は打ち切る() {
    let 地形 = 平らな地形を作る(3);
    let カプセル = カプセルを作る(位置(0.2, 3.0, 0.2), 位置(0.2, 4.0, 0.2), 0.5, 変位(0.0, -4.0, 0.0));
    let 結果 = 掃引の接触を求める(&地形, 1.0, &カプセル);
    assert_eq!(結果.調べた範囲(), 掃引の走査が調べた範囲::調べられない升目で打ち切った);
    assert_eq!(結果.最初に触れる点(), カプセルが地表に最初に触れる点::地表に触れない);
}

// 同じ入力を2回評価した結果が浮動小数点のビット列まで一致することを見る。決定性(判断14)の反証である。
#[test]
fn 同じ入力は2回評価してもビット単位で同じ結果になる() {
    let 地形 = 平らな地形を作る(4);
    let カプセル = カプセルを作る(位置(1.3, 2.7, 1.9), 位置(1.3, 3.9, 1.9), 0.4, 変位(0.7, -3.1, 0.3));
    let 最初 = 接触を取り出す(掃引の接触を求める(&地形, 1.0, &カプセル));
    let もう一度 = 接触を取り出す(掃引の接触を求める(&地形, 1.0, &カプセル));
    assert_eq!(最初.動けた割合().値().to_bits(), もう一度.動けた割合().値().to_bits());
    assert_eq!(最初.接触位置().東のメートル().to_bits(), もう一度.接触位置().東のメートル().to_bits());
    assert_eq!(最初.接触位置().天頂のメートル().to_bits(), もう一度.接触位置().天頂のメートル().to_bits());
    assert_eq!(最初.接触位置().南のメートル().to_bits(), もう一度.接触位置().南のメートル().to_bits());
    assert_eq!(最初.接触の単位法線().天頂成分().to_bits(), もう一度.接触の単位法線().天頂成分().to_bits());
    assert_eq!(最初.触れた特徴(), もう一度.触れた特徴());
}
