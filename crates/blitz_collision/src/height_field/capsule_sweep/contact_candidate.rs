//! 掃引の求解が特徴ごとに返す2つの値。触れ始める時刻を持つものと、ある時刻での隔たりを持つものである。
//!
//! 2つに分けるのは、選び方が違うからである。触れ始める候補は時刻の最小を選び、最近接は隔たりの最小を選ぶ。
//! どちらも`触れた場所`を持つが、比べる量が違うため1つの型にまとめると、どちらの量で比べるのかが
//! 呼び出し側の約束になる。
//!
//! 触れ始める候補は最近接から組む。接触の時刻でその特徴との最近接を求め直し、媒介変数が三角形と軸の範囲に
//! 収まったときだけ候補にする。同じ1つの工程から2つが出るため、時刻の答えと隔たりの答えが食い違わない。

use super::contact_place::触れた場所;
use crate::solver::掃引で動けた割合;

// ある時刻での、カプセルの軸と三角形の1つの特徴の最近接。隔たりを二乗のまま持つのは、半径との比較を
// 平方根を通さずに行えるためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 軸と特徴の最近接 {
    隔たりの二乗: f64,
    場所: 触れた場所,
}

impl 軸と特徴の最近接 {
    pub(super) fn 生成する(隔たりの二乗: f64, 場所: 触れた場所) -> Self {
        Self { 隔たりの二乗, 場所 }
    }

    pub(super) fn 隔たりの二乗(&self) -> f64 {
        self.隔たりの二乗
    }

    pub(super) fn 場所(&self) -> 触れた場所 {
        self.場所
    }
}

// 掃引の途中で初めて特徴に触れる候補。触れる時刻は掃引で動けた割合そのものであるから、その型で持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 触れ始める候補 {
    動けた割合: 掃引で動けた割合,
    場所: 触れた場所,
}

impl 触れ始める候補 {
    pub(super) fn 生成する(動けた割合: 掃引で動けた割合, 場所: 触れた場所) -> Self {
        Self { 動けた割合, 場所 }
    }

    pub(super) fn 動けた割合(&self) -> 掃引で動けた割合 {
        self.動けた割合
    }

    pub(super) fn 場所(&self) -> 触れた場所 {
        self.場所
    }
}
