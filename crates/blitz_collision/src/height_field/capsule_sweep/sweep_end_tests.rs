//! 掃引の終わりでちょうど触れる接触の反証。2次方程式の根が丸めで1をわずかに越える入力を1つ据える。
//!
//! この入力を反証として残すのは、根を0以上1以下で切り捨ててから割合を作る形では接触が消えるためである。
//! 端へ寄せる経路が受理の側に無ければ、変位の全体を動き切ったちょうどの接触が「触れなかった」に化ける。

#![allow(clippy::unwrap_used)]

use super::sweep_query_fixture::{
    カプセルを作る, 位置, 変位, 平らな地形を作る, 掃引の接触を求める, 接触を取り出す
};
use super::{地表に触れた特徴, 掃引の走査が調べた範囲};

// 高さ330.993339491018メートルから328.9007954643613メートル落ちる半径2.0925440266566975メートルのカプセル。
// 落ち切った時点の下端の球の中心と地表の隔たりは、半径を8.88かける10のマイナス16乗だけ下回る。それでも
// 2次方程式の根は1.0000000000000124と評価されるため、根をそのまま0以上1以下で判定すると接触が消える。
// 升目の一辺を1000メートルにするのは、半径より小さい升目では辺と頂点の候補が面より先に答えてしまい、
// 面と軸の端の式で起きるこの丸めを試せないためである。
#[test]
fn 掃引の終わりでちょうど触れる接触を根の丸めで取り逃さない() {
    let 地形 = 平らな地形を作る(3);
    let カプセル = カプセルを作る(
        位置(1300.0, 330.993339491018, 1700.0),
        位置(1300.0, 332.993339491018, 1700.0),
        2.0925440266566975,
        変位(0.0, -328.9007954643613, 0.0),
    );
    let 結果 = 掃引の接触を求める(&地形, 1000.0, &カプセル);
    assert_eq!(結果.調べた範囲(), 掃引の走査が調べた範囲::覆いの升目をすべて調べた);
    let 接触 = 接触を取り出す(結果);
    assert_eq!(接触.動けた割合().値(), 1.0);
    assert_eq!(接触.接触位置(), 位置(1300.0, 0.0, 1700.0));
    assert_eq!(接触.接触の単位法線().天頂成分(), 1.0);
    assert_eq!(接触.触れた特徴(), 地表に触れた特徴::三角形の面);
    assert_eq!(接触.升目の添字().東添字(), 1);
    assert_eq!(接触.升目の添字().南添字(), 1);
}
