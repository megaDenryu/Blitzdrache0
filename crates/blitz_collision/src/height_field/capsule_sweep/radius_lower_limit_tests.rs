//! 半径の下限の反証。下限を下回る半径が型付きエラーで拒まれること、下限ちょうどが受け付けられることを見る。
//!
//! カプセルどうしの詳細判定と入口が2つに割れていないことをここで見る。同じ半径が片方の問い合わせでだけ通ると、
//! 世界の側が形をどちらへ渡したかで答えが変わる。

#![allow(clippy::unwrap_used)]

use super::super::grid_origin_displacement::高さ場の中の変位;
use super::super::grid_origin_position::高さ場の格子原点からの位置;
use super::capsule::高さ場を掃引するカプセル;
use super::error::カプセルの掃引の問い合わせエラー;
use super::radius_lower_limit::高さ場を掃引するカプセルの半径の下限メートル;

#[test]
fn 下限を下回る半径のカプセルは型付きエラーで拒む() {
    let 始点 = 高さ場の格子原点からの位置::生成する(0.0, 0.0, 0.0).unwrap();
    let 終点 = 高さ場の格子原点からの位置::生成する(0.0, 1.0, 0.0).unwrap();
    let 変位 = 高さ場の中の変位::生成する(0.0, -1.0, 0.0).unwrap();
    assert_eq!(
        高さ場を掃引するカプセル::生成する(始点, 終点, 1.0e-200, 変位),
        Err(カプセルの掃引の問い合わせエラー::カプセルの半径が下限を下回っている)
    );
}

#[test]
fn 下限ちょうどの半径のカプセルは受け付ける() {
    let 始点 = 高さ場の格子原点からの位置::生成する(0.0, 0.0, 0.0).unwrap();
    let 終点 = 高さ場の格子原点からの位置::生成する(0.0, 1.0, 0.0).unwrap();
    let 変位 = 高さ場の中の変位::生成する(0.0, -1.0, 0.0).unwrap();
    assert!(高さ場を掃引するカプセル::生成する(始点, 終点, 高さ場を掃引するカプセルの半径の下限メートル, 変位).is_ok());
}
