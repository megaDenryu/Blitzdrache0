//! 求解が特徴ごとの式を組むときに何度も使う幾何の読み替え。触れるのは保持したカプセルと三角形だけである。
//!
//! この工程を分けるのは、面・辺・頂点の3つの求解が同じ読み替えを使うためである。読み替えをそれぞれの
//! 求解へ写すと、時刻での軸の位置の作り方が3つに分かれ、同じ時刻で違う位置を指す余地が生まれる。

use super::super::grid_origin_displacement::高さ場の中の変位;
use super::super::grid_origin_position::高さ場の格子原点からの位置;
use super::super::unit_direction::地表の単位向き;
use super::axis_end::軸の端;
use super::contact_solver::カプセルと三角形の接触の求解;

impl カプセルと三角形の接触の求解<'_> {
    pub(super) fn 半径の二乗(&self) -> f64 {
        self.カプセル().半径のメートル() * self.カプセル().半径のメートル()
    }

    pub(super) fn 掃引の変位(&self) -> 高さ場の中の変位 {
        self.カプセル().掃引の変位()
    }

    // 軸の始点から終点へ向かう変位。長さ0の軸(球)では零になる。
    pub(super) fn 軸の変位(&self) -> 高さ場の中の変位 {
        self.カプセル().軸の変位を求める()
    }

    // 三角形の上向きの単位法線を、内積と外積の取れる変位として読む。丸めを1つも通さない読み替えである。
    pub(super) fn 上向きの法線の変位(&self) -> 高さ場の中の変位 {
        高さ場の中の変位::単位向きから読む(self.三角形().上向きの単位法線())
    }

    // 掃引の始まりでの軸の端の位置。
    pub(super) fn 軸の端の位置(&self, 端: 軸の端) -> 高さ場の格子原点からの位置 {
        self.カプセル().軸の端点を並べる()[端.並びの位置()]
    }

    // 三角形の頂点から、時刻での軸の端へ向かう変位。掃引はカプセル全体を同じだけ動かすため、
    // この変位は時刻の1次式である。
    pub(super) fn 頂点から時刻の軸の端への変位(
        &self, 頂点の並びの位置: usize, 端: 軸の端, 時刻: f64
    ) -> 高さ場の中の変位 {
        let 始まりの変位 = self.三角形().頂点の位置(頂点の並びの位置).終点までの変位を求める(self.軸の端の位置(端));
        始まりの変位.加える(self.掃引の変位().実数倍する(時刻))
    }

    // 三角形の辺の変位。並びの位置の頂点から次の位置の頂点へ向かう。
    pub(super) fn 辺の変位(&self, 辺の並びの位置: usize) -> 高さ場の中の変位 {
        self.三角形()
            .頂点の位置(辺の並びの位置)
            .終点までの変位を求める(self.三角形().頂点の位置(辺の並びの位置 + 1))
    }

    // 接触点から軸へ向かう変位を、接触の単位法線へ正す。隔たりが0でこの向きが定まらないときは、
    // 地表の上向きの単位法線を代わりに使う。貫くほど深く重なった場合に向きを持たない答えを返さないためである。
    pub(super) fn 接触の単位法線を正す(&self, 接触点から軸への変位: 高さ場の中の変位) -> 地表の単位向き<f64> {
        接触点から軸への変位
            .長さで正した単位向きを求める()
            .unwrap_or_else(|| self.三角形().上向きの単位法線())
    }
}
