//! 三角形の面と軸の端の接触。触れるのは三角形の平面と、軸の端に置いた半径の球だけである。
//!
//! 球と平面の隔たりは時刻の1次式であるから、隔たりが半径に等しくなる時刻も1次で決まる。それでも2乗した形の
//! 方程式で解くのは、地表の表からも裏からも触れうるためである。1次式のまま解くと符号ごとに2本の式になる。
//! 2乗した式の2次の係数は変位の法線成分の2乗であり、法線と垂直に動く掃引では0になって1次式へ退化する。
//!
//! 平面は三角形より広いため、根の時刻での接触点が三角形の内側に無ければその根を捨てる。
//! 捨てた接触は、面ではなく辺か頂点の候補が答える。

use super::super::unit_direction::地表の単位向き;
use super::axis_end::軸の端;
use super::contact_candidate::軸と特徴の最近接;
use super::contact_place::触れた場所;
use super::contact_solver::カプセルと三角形の接触の求解;
use super::error::カプセルの掃引の問い合わせエラー;
use super::feature::地表に触れた特徴;
use super::quadratic::掃引の2次方程式;

impl カプセルと三角形の接触の求解<'_> {
    pub(super) fn 面と軸の端の方程式を組む(&self, 端: 軸の端) -> 掃引の2次方程式 {
        let 法線 = self.上向きの法線の変位();
        let 始まりの隔たり = self.頂点から時刻の軸の端への変位(0, 端, 0.0).内積(法線);
        let 隔たりの速度 = self.掃引の変位().内積(法線);
        掃引の2次方程式::生成する(
            隔たりの速度 * 隔たりの速度,
            2.0 * 始まりの隔たり * 隔たりの速度,
            始まりの隔たり * 始まりの隔たり - self.半径の二乗(),
        )
    }

    /// 時刻での、三角形の面と軸の端の最近接。球の中心を平面へ落とした点が三角形の外にあるなら、
    /// その点は面での接触ではないため`None`を返す。
    pub(super) fn 面と軸の端の最近接を求める(
        &self,
        端: 軸の端,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, カプセルの掃引の問い合わせエラー> {
        let 法線 = self.上向きの法線の変位();
        let 頂点から軸へ = self.頂点から時刻の軸の端への変位(0, 端, 時刻);
        let 符号付きの隔たり = 頂点から軸へ.内積(法線);
        let 接触位置 = self
            .軸の端の位置(端)
            .変位だけ進んだ位置を求める(self.掃引の変位().実数倍する(時刻).引く(法線.実数倍する(符号付きの隔たり)))?;
        if !self.三角形().面の上の点が内側にあるか(接触位置) {
            return Ok(None);
        }
        Ok(Some(軸と特徴の最近接::生成する(
            符号付きの隔たり * 符号付きの隔たり,
            触れた場所::生成する(接触位置, self.面に触れた単位法線(符号付きの隔たり), 地表に触れた特徴::三角形の面),
        )))
    }

    /// 面に触れたときの接触の単位法線。地表の表から触れたなら上向きの単位法線そのもの、裏から触れたなら
    /// その逆向きである。差を正す割り算を通さないため、高さの問い合わせが返す法線とビット単位で同じ値になる。
    fn 面に触れた単位法線(&self, 符号付きの隔たり: f64) -> 地表の単位向き<f64> {
        let 上向き = self.三角形().上向きの単位法線();
        if 符号付きの隔たり < 0.0 {
            上向き.逆を向く向き()
        } else {
            上向き
        }
    }
}
