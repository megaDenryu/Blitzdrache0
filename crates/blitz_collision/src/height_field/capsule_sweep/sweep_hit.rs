//! 掃引したカプセルが地表に最初に触れた点と、変位の全体を動いても触れなかったことを表す枝。

use super::contact::掃引したカプセルの地表への接触;

/// 掃引したカプセルが地表に最初に触れた点。変位の全体を動いても触れなかった枝と、触れた接触を持つ枝の2つである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum カプセルが地表に最初に触れる点 {
    /// 変位の全体を動いても地表に触れなかった。
    地表に触れない,
    /// 変位の途中で地表に触れ、その最初の接触を持つ。
    地表に触れる(掃引したカプセルの地表への接触),
}
