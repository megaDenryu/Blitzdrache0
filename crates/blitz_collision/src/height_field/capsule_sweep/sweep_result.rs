//! カプセルの掃引と高さ場の接触の結果: 掃引の問い合わせが返す2つの軸を1つにまとめた値である。
//! 1つ目の軸は最初に触れる点そのもの、2つ目の軸はその答えが確定的かどうかである。
//!
//! 2軸に分ける理由は`掃引の走査が調べた範囲`が持つ。世界の側はこの2軸目を問い合わせの完全性へ写す。
//! 触れる点を答えるのは、覆いの升目をすべて調べ切れたときだけである。1つでも答えられない升目があれば、
//! その升目にもっと早い接触がありうるため、見つけた接触を捨てて打ち切りの側で答える。

use super::contact::掃引したカプセルの地表への接触;
use super::scanned_range::掃引の走査が調べた範囲;
use super::sweep_hit::カプセルが地表に最初に触れる点;

/// カプセルの掃引と高さ場の接触の結果。最初に触れる点と、その答えが確定的かどうかの2つの軸を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct カプセルの掃引と高さ場の接触の結果 {
    最初に触れる点: カプセルが地表に最初に触れる点,
    調べた範囲: 掃引の走査が調べた範囲,
}

impl カプセルの掃引と高さ場の接触の結果 {
    pub(super) fn 覆いをすべて調べて接触を見つけた(接触: 掃引したカプセルの地表への接触) -> Self {
        Self {
            最初に触れる点: カプセルが地表に最初に触れる点::地表に触れる(接触),
            調べた範囲: 掃引の走査が調べた範囲::覆いの升目をすべて調べた,
        }
    }

    pub(super) fn 覆いをすべて調べて触れなかった() -> Self {
        Self {
            最初に触れる点: カプセルが地表に最初に触れる点::地表に触れない,
            調べた範囲: 掃引の走査が調べた範囲::覆いの升目をすべて調べた,
        }
    }

    pub(super) fn 調べられない升目で打ち切った() -> Self {
        Self {
            最初に触れる点: カプセルが地表に最初に触れる点::地表に触れない,
            調べた範囲: 掃引の走査が調べた範囲::調べられない升目で打ち切った,
        }
    }

    /// 掃引したカプセルが地表に最初に触れた点。覆いを調べ切れずに打ち切った場合は触れない側で返る。
    pub fn 最初に触れる点(&self) -> カプセルが地表に最初に触れる点 {
        self.最初に触れる点
    }

    /// 覆いの升目をすべて調べ切れたか。世界の側はこの軸を問い合わせ完全性へ写す。
    pub fn 調べた範囲(&self) -> 掃引の走査が調べた範囲 {
        self.調べた範囲
    }
}
