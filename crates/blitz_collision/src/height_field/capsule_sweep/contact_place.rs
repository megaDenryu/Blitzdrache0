//! 触れた場所: 三角形の上のどの点に、どの向きから、どの特徴として触れたかである。
//! 時刻も隔たりも持たない。同じ場所が「掃引の途中で初めて触れる場所」としても「掃引の始まりで最も近い場所」
//! としても現れ、時刻と隔たりはその2つの用途がそれぞれ持つためである。
//!
//! 接触の単位法線は、接触点からカプセルの軸へ向かう向きである。面に触れたときはその三角形の上向きの
//! 単位法線(裏側からならその逆向き)そのものであり、丸めを1つも通さない。辺と頂点に触れたときは、
//! 接触点から軸の最近接点へ向かう変位を長さ1に正した向きである。
//! 隔たりが0でこの向きが定まらない場合は、地表の上向きの単位法線を代わりに使う。

use super::super::grid_origin_position::高さ場の格子原点からの位置;
use super::super::unit_direction::地表の単位向き;
use super::feature::地表に触れた特徴;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 触れた場所 {
    接触位置: 高さ場の格子原点からの位置,
    接触の単位法線: 地表の単位向き<f64>,
    特徴: 地表に触れた特徴,
}

impl 触れた場所 {
    pub(super) fn 生成する(
        接触位置: 高さ場の格子原点からの位置, 接触の単位法線: 地表の単位向き<f64>, 特徴: 地表に触れた特徴
    ) -> Self {
        Self {
            接触位置,
            接触の単位法線,
            特徴,
        }
    }

    pub(super) fn 接触位置(&self) -> 高さ場の格子原点からの位置 {
        self.接触位置
    }

    pub(super) fn 接触の単位法線(&self) -> 地表の単位向き<f64> {
        self.接触の単位法線
    }

    pub(super) fn 特徴(&self) -> 地表に触れた特徴 {
        self.特徴
    }
}
