//! 升目の地表の三角形: 升目を2つに割った三角形の1つを、3つの格子点の位置として持ったものである。
//! 区分線形の面が高さと傾きだけを持つのに対し、こちらは辺と頂点の位置を持つ。掃引の接触は面の内側だけでなく
//! 辺と頂点でも起きるため、平面の式では足りず実際の3点が要るからである。
//!
//! 上向きの単位法線は自分で組み直さず、区分線形の面の傾きから導いたものをそのまま持つ。3点の外積から
//! 求め直すと、同じ三角形の法線が高さの問い合わせと掃引の問い合わせで別のビット列になるためである。
//! 3頂点の並びは奥側が手前左・奥左・奥右、手前側が手前左・手前右・奥右である。この並びの巻き方向は
//! 2つの三角形で揃っていないため、面の裏表の判定にはこの並びから求めた向きでなく上向きの単位法線を使う。

use super::super::cell_corner::升目の隅;
use super::super::cell_corner_heights::升目の四隅の高さ;
use super::super::cell_edge::升目の一辺;
use super::super::cell_index::升目の格子添字;
use super::super::cell_ratio::升目の中の比;
use super::super::grid_origin_position::高さ場の格子原点からの位置;
use super::super::triangle::升目の三角形;
use super::super::unit_direction::地表の単位向き;
use super::error::カプセルの掃引の問い合わせエラー;

pub(super) struct 升目の地表の三角形 {
    頂点の隅: [升目の隅; 3],
    頂点の位置: [高さ場の格子原点からの位置; 3],
    上向きの単位法線: 地表の単位向き<f64>,
}

impl 升目の地表の三角形 {
    pub(super) fn 生成する(
        添字: 升目の格子添字,
        四隅: &升目の四隅の高さ<f64>,
        一辺: 升目の一辺<f64>,
        三角形: 升目の三角形,
    ) -> Result<Self, カプセルの掃引の問い合わせエラー> {
        let 頂点の隅 = 三角形の頂点の隅を並べる(三角形);
        let 傾き = 四隅
            .指定した三角形の地表の面を求める(三角形, 升目の中の比::生成する(0.0, 0.0)?, 一辺)?
            .傾き();
        let 頂点の位置 = [
            格子点の位置を組む(添字, 頂点の隅[0], 四隅, 一辺)?,
            格子点の位置を組む(添字, 頂点の隅[1], 四隅, 一辺)?,
            格子点の位置を組む(添字, 頂点の隅[2], 四隅, 一辺)?,
        ];
        Ok(Self {
            頂点の隅,
            頂点の位置,
            上向きの単位法線: 傾き.上向きの単位法線(),
        })
    }

    pub(super) fn 上向きの単位法線(&self) -> 地表の単位向き<f64> {
        self.上向きの単位法線
    }

    pub(super) fn 頂点の隅(&self, 並びの位置: usize) -> 升目の隅 {
        self.頂点の隅[並びの位置 % 3]
    }

    pub(super) fn 頂点の位置(&self, 並びの位置: usize) -> 高さ場の格子原点からの位置 {
        self.頂点の位置[並びの位置 % 3]
    }
}

/// 三角形を張る3つの隅を、`crates/blitz_collision/src/height_field/triangle.rs`が定めた並びで返す。
fn 三角形の頂点の隅を並べる(三角形: 升目の三角形) -> [升目の隅; 3] {
    match 三角形 {
        升目の三角形::奥側 => [升目の隅::手前左, 升目の隅::奥左, 升目の隅::奥右],
        升目の三角形::手前側 => [升目の隅::手前左, 升目の隅::手前右, 升目の隅::奥右],
    }
}

/// 格子点1つの位置。水平の2成分は升目の添字と隅から、天頂の成分はその隅の高さから組む。
/// 位置の生成が成分の絶対値の上限を課すため、一辺の大きい高さ場で格子点が上限を越える升目は型付きエラーになる。
/// 掃引の係数が桁あふれしないことの算術は格子点も上限に収まることを使うため、そこは答えられない升目である。
/// 参照: `crates/blitz_collision/src/height_field/length_limit.rs`
fn 格子点の位置を組む(
    添字: 升目の格子添字,
    隅: 升目の隅,
    四隅: &升目の四隅の高さ<f64>,
    一辺: 升目の一辺<f64>,
) -> Result<高さ場の格子原点からの位置, カプセルの掃引の問い合わせエラー> {
    let 東の実数添字 = f64::from(添字.東添字()) + f64::from(隅.東へ進む格子点の数());
    let 南の実数添字 = f64::from(添字.南添字()) + f64::from(隅.南へ進む格子点の数());
    Ok(高さ場の格子原点からの位置::生成する(
        一辺.実数添字をメートルへ直す(東の実数添字),
        四隅.隅の高さ(隅),
        一辺.実数添字をメートルへ直す(南の実数添字),
    )?)
}
