//! 三角形1つを調べた答え。掃引の始まりから触れていた場合と、掃引の途中で触れ始める場合と、
//! 変位の全体を動いても触れない場合の3つである。
//!
//! 前の2つを別の枝にするのは、覆いの中で選ぶ量が違うためである。始まりから触れている三角形どうしは
//! 隔たりの二乗の小さいほうを選び(接触の法線を最も近い特徴から導くため)、途中で触れ始める三角形どうしは
//! 時刻の早いほうを選ぶ。始まりから触れている三角形が1つでもあれば、掃引はそもそも一歩も動けないため、
//! 途中で触れ始める答えより優先する。

use super::contact::掃引したカプセルの地表への接触;
use crate::solver::掃引で動けた割合;

pub(super) enum 三角形の中の接触 {
    掃引の始まりから触れている {
        隔たりの二乗: f64,
        接触: 掃引したカプセルの地表への接触,
    },
    掃引の途中で触れ始める {
        動けた割合: 掃引で動けた割合,
        接触: 掃引したカプセルの地表への接触,
    },
    どこでも触れない,
}
