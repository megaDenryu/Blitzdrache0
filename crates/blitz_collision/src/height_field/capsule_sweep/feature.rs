//! 地表に触れた特徴: カプセルが三角形のどの部分に触れたかである。面・辺・頂点の3つを区別する。
//!
//! 区別を残すのは、接触の単位法線の出どころが3つで違うためである。面に触れたときの法線はその三角形の
//! 上向きの単位法線そのものであり、辺と頂点に触れたときの法線は接触点からカプセルの軸へ向かう向きである。
//! 辺は両端の隅の名前で表す。辺の枝が持つ`始まりの隅`と`終わりの隅`は、その辺を張る2つの格子点である。
//!
//! 隣り合う升目や2つの三角形が同じ辺・同じ頂点を共有するため、同じ幾何の特徴が別の升目の名前で返ることがある。
//! どちらの名前も同じ点を指しており、接触の位置と法線は一致する。

use super::super::cell_corner::升目の隅;

/// カプセルが三角形のどの部分に触れたか。`三角形の面`は面の内側、`三角形の辺`は始まりの隅と終わりの隅が張る辺の上、`三角形の頂点`はその隅の格子点である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[allow(missing_docs)] // 枝の説明は型の`///`が持つ。枝ごとの`///`は宣言の間のコメント行になり規約に反する
pub enum 地表に触れた特徴 {
    三角形の面,
    三角形の辺 {
        始まりの隅: 升目の隅,
        終わりの隅: 升目の隅,
    },
    三角形の頂点(升目の隅),
}
