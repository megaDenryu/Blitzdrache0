//! カプセルと三角形の接触の求解: 掃引するカプセル1つと地表の三角形1つを受け取り、
//! 「掃引の途中で最初に触れる接触」と「掃引の始まりで最も近い特徴」の2つに答える操作サービスである。
//! カプセルと三角形をコンストラクタで受け取って保持するため、どの問いの署名にも幾何が現れない。
//!
//! 2つの問いを1つの型が持つのは、どちらも同じ20通りの候補を同じ順に数え、同じ最近接の工程を通るためである。
//! 掃引の始まりで既に半径以内に居るなら動ける割合は0であり、そのときの法線は最も近い特徴から導く。
//! これは線分の問い合わせが「始点が地表の下なら交差時刻0」とした設計と同じ考えである。
//! 参照: `crates/blitz_collision/src/height_field/cell_segment_intersection.rs`

use super::candidate::接触の特徴の候補;
use super::capsule::高さ場を掃引するカプセル;
use super::contact_candidate::{触れ始める候補, 軸と特徴の最近接};
use super::error::カプセルの掃引の問い合わせエラー;
use super::surface_triangle::升目の地表の三角形;
use crate::solver::掃引で動けた割合;
use crate::solver::最も小さい量の候補だけを覚える器;

pub(super) struct カプセルと三角形の接触の求解<'掃引> {
    カプセル: &'掃引 高さ場を掃引するカプセル,
    三角形: &'掃引 升目の地表の三角形,
}

impl<'掃引> カプセルと三角形の接触の求解<'掃引> {
    pub(super) fn 生成する(カプセル: &'掃引 高さ場を掃引するカプセル, 三角形: &'掃引 升目の地表の三角形) -> Self {
        Self { カプセル, 三角形 }
    }

    pub(super) fn カプセル(&self) -> &高さ場を掃引するカプセル {
        self.カプセル
    }

    pub(super) fn 三角形(&self) -> &升目の地表の三角形 {
        self.三角形
    }

    // 掃引の途中で最初に触れる接触。どの候補も触れないなら`None`を返す。
    pub(super) fn 掃引の途中で最初に触れる接触を求める(
        &self,
    ) -> Result<Option<触れ始める候補>, カプセルの掃引の問い合わせエラー> {
        let mut 最小 = 最も小さい量の候補だけを覚える器::まだ何も無い状態から始める();
        for 候補 in 接触の特徴の候補::並べる() {
            if let Some(触れ始める) = self.候補が最初に触れる時刻を求める(候補)? {
                最小.候補を1つ数える(触れ始める.動けた割合().値(), 触れ始める);
            }
        }
        Ok(最小.覚えている候補を取り出す())
    }

    // 掃引の始まりで、カプセルの軸に最も近い特徴とその隔たり。呼び出し側はこの隔たりを半径と比べ、
    // 半径以下なら動く前から触れていたものとして扱う。
    // 軸そのものが三角形を貫いている場合は隔たりが0であり、面を貫いた点を最近接として返す。
    pub(super) fn 掃引の始まりで最も近い特徴を求める(
        &self,
    ) -> Result<Option<軸と特徴の最近接>, カプセルの掃引の問い合わせエラー> {
        if let Some(貫いた場所) = self.軸が三角形を貫く場所を求める()? {
            return Ok(Some(貫いた場所));
        }
        let mut 最小 = 最も小さい量の候補だけを覚える器::まだ何も無い状態から始める();
        for 候補 in 接触の特徴の候補::並べる() {
            if let Some(最近接) = self.候補の最近接を求める(候補, 0.0)? {
                最小.候補を1つ数える(最近接.隔たりの二乗(), 最近接);
            }
        }
        Ok(最小.覚えている候補を取り出す())
    }

    // 1つの候補について、掃引の中に在る最小の根を探す。根を割合として受理するのは`掃引で動けた割合`であり、
    // 端をわずかに越えた根はそこで端の正準値へ寄る。寄せた割合で最近接を求め直し、媒介変数が三角形と軸の
    // 範囲に収まったときだけ候補にする。収まらない根は、平面や直線という三角形やカプセルより広がった形での
    // 接触であり、実際には触れていない。
    fn 候補が最初に触れる時刻を求める(
        &self,
        候補: 接触の特徴の候補,
    ) -> Result<Option<触れ始める候補>, カプセルの掃引の問い合わせエラー> {
        let Some(方程式) = self.候補の方程式を組む(候補) else {
            return Ok(None);
        };
        for 根 in 方程式.根を小さい順に並べる() {
            let Some(動けた割合) = 掃引で動けた割合::根を端へ寄せて受理する(根) else {
                continue;
            };
            if let Some(最近接) = self.候補の最近接を求める(候補, 動けた割合.値())? {
                return Ok(Some(触れ始める候補::生成する(動けた割合, 最近接.場所())));
            }
        }
        Ok(None)
    }
}
