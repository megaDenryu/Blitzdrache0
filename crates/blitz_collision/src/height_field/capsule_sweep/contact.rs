//! 掃引したカプセルの地表への接触。持つのは幾何学的な事実だけであり、そこで止まるか滑るか登れるかという
//! 意味付けは持たない。
//!
//! 動けた割合と接触位置は同じ1つの時刻から導いている。接触位置は三角形の上の点であり、その時刻のカプセルの
//! 表面もその点を通る。接触の単位法線は接触位置からカプセルの軸へ向かう向きであり、面に触れたときは
//! その三角形の上向きの単位法線(裏から触れたならその逆向き)と同じ値である。

use super::super::cell_index::升目の格子添字;
use super::super::grid_origin_position::高さ場の格子原点からの位置;
use super::super::triangle::升目の三角形;
use super::super::unit_direction::地表の単位向き;
use super::contact_place::触れた場所;
use super::feature::地表に触れた特徴;
use super::ratio::掃引で動けた割合;

/// 掃引したカプセルが地表へ触れた1つの事実。動けた割合・接触位置・接触の単位法線・どの升目のどちらの三角形のどの特徴かを持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 掃引したカプセルの地表への接触 {
    動けた割合: 掃引で動けた割合,
    場所: 触れた場所,
    升目の添字: 升目の格子添字,
    三角形: 升目の三角形,
}

impl 掃引したカプセルの地表への接触 {
    pub(super) fn 生成する(
        動けた割合: 掃引で動けた割合, 場所: 触れた場所, 升目の添字: 升目の格子添字, 三角形: 升目の三角形
    ) -> Self {
        Self {
            動けた割合,
            場所,
            升目の添字,
            三角形,
        }
    }

    /// 掃引の変位のうち、地表に触れるまでに動けた分の割合。動く前から触れていた場合は0である。
    pub fn 動けた割合(&self) -> 掃引で動けた割合 {
        self.動けた割合
    }

    /// 三角形の上の接触点。その時刻のカプセルの表面もこの点を通る。
    pub fn 接触位置(&self) -> 高さ場の格子原点からの位置 {
        self.場所.接触位置()
    }

    /// 接触位置からカプセルの軸へ向かう単位向き。
    pub fn 接触の単位法線(&self) -> 地表の単位向き<f64> {
        self.場所.接触の単位法線()
    }

    /// 三角形の面・辺・頂点のどれに触れたか。
    pub fn 触れた特徴(&self) -> 地表に触れた特徴 {
        self.場所.特徴()
    }

    /// 触れた三角形が属する升目の格子添字。
    pub fn 升目の添字(&self) -> 升目の格子添字 {
        self.升目の添字
    }

    /// 触れたのが升目のどちらの三角形か。
    pub fn 三角形(&self) -> 升目の三角形 {
        self.三角形
    }
}
