//! 掃引で動けた割合: 掃引の変位のうち、地表に触れるまでに動けた分の割合である。0以上1以下の無次元量であり、
//! 0は動く前から既に触れていたこと、1は変位の全体を動けたことを表す。
//!
//! 裸の実数で運ばないのは、この量が長さでも高さでも升目の中の比でも線分の媒介変数でもない別の量であり、
//! 実数のままではそれらと取り違えても型が通るためである。

use super::error::カプセルの掃引の問い合わせエラー;

#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 掃引で動けた割合(f64);

impl 掃引で動けた割合 {
    pub fn 生成する(値: f64) -> Result<Self, カプセルの掃引の問い合わせエラー> {
        if !値.is_finite() || !(0.0..=1.0).contains(&値) {
            return Err(カプセルの掃引の問い合わせエラー::掃引で動けた割合が範囲外);
        }
        Ok(Self(値))
    }

    /// 0以上1以下からわずかに外れた値を端へ寄せて作る。接触の時刻は2次方程式の根であり、変位の全体を
    /// 動き切ったちょうどの接触が1をほんの少し越えることがある。非有限の値は寄せずに型付きエラーで拒む。
    pub(super) fn 端へ寄せて生成する(値: f64) -> Result<Self, カプセルの掃引の問い合わせエラー> {
        if !値.is_finite() {
            return Err(カプセルの掃引の問い合わせエラー::掃引で動けた割合が範囲外);
        }
        Ok(Self(値.clamp(0.0, 1.0)))
    }

    /// 動く前から既に触れていた場合の割合。
    pub(super) fn 一歩も動けなかった() -> Self {
        Self(0.0)
    }

    pub fn 値(&self) -> f64 {
        self.0
    }
}
