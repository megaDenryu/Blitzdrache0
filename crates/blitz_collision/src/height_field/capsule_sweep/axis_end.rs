//! 軸の端: カプセルの軸の2つの端のどちらかである。カプセルの両端は半球であり、その半球が三角形へ触れる
//! 接触は、軸の端に置いた球の接触と同じものになる。掃引の求解が球として扱う部分を名前で指すために置く。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 軸の端 {
    始点の側,
    終点の側,
}

impl 軸の端 {
    /// 2つの端を、求解が候補を数える順に並べる。
    pub(super) fn 並べる() -> [Self; 2] {
        [Self::始点の側, Self::終点の側]
    }

    /// `高さ場を掃引するカプセル::軸の端点を並べる`が返す並びの中の位置。
    pub(super) fn 並びの位置(self) -> usize {
        match self {
            Self::始点の側 => 0,
            Self::終点の側 => 1,
        }
    }
}
