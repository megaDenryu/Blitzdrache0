//! 長さの絶対値の上限ちょうどの入力で、掃引の候補のうち係数が最も大きく育つ辺と軸の内側の式が
//! 桁あふれしないことの反証。既にある上限の反証は入口が上限を越える入力を拒むことだけを見ており、
//! 上限に収まる入力で最悪の候補の算術がどこまで育つかを見ていなかった。
//! 参照: `crates/blitz_collision/src/height_field/length_limit.rs`
//!
//! 組む掃引。上限をBと書く。一辺がBの升目(0, 0)の手前側の三角形を、四隅の高さをすべてマイナスBにして置く。
//! 3つの頂点は(0, -B, 0)・(B, -B, 0)・(B, -B, B)であり、並びの位置0の辺は東へ長さBに伸びる。
//! カプセルの軸は東がBの半分の位置で南マイナスBから南Bへ張り、半径はB、掃引の変位は天頂へマイナスBである。
//! 辺は東を、軸は南を向いてねじれの位置にあるから、両方に垂直な向きは天頂を向く長さ2Bの2乗の変位になる。
//! 軸と辺の隔たりは掃引の始まりで2B、掃引の終わりでBであるから、半径Bのカプセルは動けた割合1でちょうど触れる。
//! この掃引の値はすべて2の冪の整数倍であるため、期待値を厳密な等号で書ける。

#![allow(clippy::unwrap_used)]

use super::super::{
    升目の一辺, 升目の三角形, 升目の四隅の高さ, 升目の格子添字, 高さ場の中の変位, 高さ場の問い合わせが受け付ける長さの絶対値の上限メートル,
    高さ場の格子原点からの位置,
};
use super::axis_end::軸の端;
use super::capsule::高さ場を掃引するカプセル;
use super::contact_solver::カプセルと三角形の接触の求解;
use super::surface_triangle::升目の地表の三角形;

const 長さの上限メートル: f64 = 高さ場の問い合わせが受け付ける長さの絶対値の上限メートル;

fn 長さの上限の六乗を求める() -> f64 {
    let 三乗 = 長さの上限メートル * 長さの上限メートル * 長さの上限メートル;
    三乗 * 三乗
}

fn 一辺も高さも上限の升目の三角形を作る() -> 升目の地表の三角形 {
    let 四隅 = 升目の四隅の高さ::生成する(-長さの上限メートル, -長さの上限メートル, -長さの上限メートル, -長さの上限メートル).unwrap();
    let 一辺 = 升目の一辺::生成する(長さの上限メートル).unwrap();
    升目の地表の三角形::生成する(升目の格子添字::生成する(0, 0), &四隅, 一辺, 升目の三角形::手前側).unwrap()
}

fn 辺をまたぐ軸で真下へ落ちるカプセルを作る() -> 高さ場を掃引するカプセル {
    let 軸の始点 = 高さ場の格子原点からの位置::生成する(長さの上限メートル / 2.0, 長さの上限メートル, -長さの上限メートル).unwrap();
    let 軸の終点 = 高さ場の格子原点からの位置::生成する(長さの上限メートル / 2.0, 長さの上限メートル, 長さの上限メートル).unwrap();
    let 掃引の変位 = 高さ場の中の変位::生成する(0.0, -長さの上限メートル, 0.0).unwrap();
    高さ場を掃引するカプセル::生成する(軸の始点, 軸の終点, 長さの上限メートル, 掃引の変位).unwrap()
}

// 求解が組む係数を同じ順で組み直し、Bの6乗と12乗まで育った値が倍精度に収まることを見る。
#[test]
fn 上限ちょうどの掃引でも辺と軸の内側の係数と判別式は倍精度に収まる() {
    let 三角形 = 一辺も高さも上限の升目の三角形を作る();
    let カプセル = 辺をまたぐ軸で真下へ落ちるカプセルを作る();
    let 求解 = カプセルと三角形の接触の求解::生成する(&カプセル, &三角形);
    let 上限の二乗 = 長さの上限メートル * 長さの上限メートル;
    let 上限の三乗 = 上限の二乗 * 長さの上限メートル;
    let 上限の六乗 = 長さの上限の六乗を求める();
    let 両方に垂直な向き = 求解.軸の変位().外積(求解.辺の変位(0));
    assert_eq!(両方に垂直な向き.天頂のメートル(), 2.0 * 上限の二乗);
    assert_eq!(両方に垂直な向き.長さの二乗(), 4.0 * 上限の二乗 * 上限の二乗);
    let 始まりの射影 = 求解.頂点から時刻の軸の端への変位(0, 軸の端::始点の側, 0.0).内積(両方に垂直な向き);
    let 射影の速度 = 求解.掃引の変位().内積(両方に垂直な向き);
    assert_eq!(始まりの射影, 4.0 * 上限の三乗);
    assert_eq!(射影の速度, -2.0 * 上限の三乗);
    let 二次の係数 = 射影の速度 * 射影の速度;
    let 一次の係数 = 2.0 * 始まりの射影 * 射影の速度;
    let 定数項 = 始まりの射影 * 始まりの射影 - 求解.半径の二乗() * 両方に垂直な向き.長さの二乗();
    assert_eq!(二次の係数, 4.0 * 上限の六乗);
    assert_eq!(一次の係数, -16.0 * 上限の六乗);
    assert_eq!(定数項, 12.0 * 上限の六乗);
    let 判別式 = 一次の係数 * 一次の係数 - 4.0 * 二次の係数 * 定数項;
    assert!(判別式.is_finite());
    assert_eq!(判別式, 64.0 * 上限の六乗 * 上限の六乗);
}

// 導いた上界そのものが倍精度に収まることを見る。上界は判別式が11059200かける上限の12乗以下という形であり、
// 上限が2の24乗であるときこれは倍精度の最大値の10のマイナス214乗倍を下回る。
#[test]
fn 辺と軸の内側の判別式の上界は倍精度の最大値を大きく下回る() {
    let 上限の六乗 = 長さの上限の六乗を求める();
    let 判別式の上界 = 11_059_200.0 * 上限の六乗 * 上限の六乗;
    assert!(判別式の上界.is_finite());
    assert!(判別式の上界 * 1.0e214 < f64::MAX);
}

// 隔たりが半径に等しくなるのは、4Bの3乗から2Bの3乗かける時刻を引いた射影の二乗が、半径の二乗Bの2乗かける
// 向きの長さの二乗4Bの4乗に等しいときである。両辺を4Bの6乗で割ると2から時刻を引いた値の二乗が1になり、
// 根は1と3になる。掃引の中に在るのは1のほうであり、掃引の終わりでちょうど触れる。
#[test]
fn 上限ちょうどの掃引で辺と軸の内側の根は手で解いた値と一致する() {
    let 三角形 = 一辺も高さも上限の升目の三角形を作る();
    let カプセル = 辺をまたぐ軸で真下へ落ちるカプセルを作る();
    let 求解 = カプセルと三角形の接触の求解::生成する(&カプセル, &三角形);
    let 方程式 = 求解.辺と軸の内側の方程式を組む(0).unwrap();
    let 根の一覧: Vec<f64> = 方程式.根を小さい順に並べる().collect();
    assert_eq!(根の一覧, vec![1.0, 3.0]);
}

// 根が実際の接触であることを見る。掃引の終わりで軸は天頂0へ下がり、辺との隔たりはちょうど半径Bになる。
// 最近接点は辺の中央であり、その位置は東がBの半分・天頂がマイナスB・南が0である。
#[test]
fn 上限ちょうどの掃引の終わりの最近接は半径ちょうどの隔たりになる() {
    let 三角形 = 一辺も高さも上限の升目の三角形を作る();
    let カプセル = 辺をまたぐ軸で真下へ落ちるカプセルを作る();
    let 求解 = カプセルと三角形の接触の求解::生成する(&カプセル, &三角形);
    let 最近接 = 求解.辺と軸の内側の最近接を求める(0, 1.0).unwrap().unwrap();
    assert_eq!(最近接.隔たりの二乗(), 長さの上限メートル * 長さの上限メートル);
    assert_eq!(
        最近接.場所().接触位置(),
        高さ場の格子原点からの位置::生成する(長さの上限メートル / 2.0, -長さの上限メートル, 0.0).unwrap()
    );
}
