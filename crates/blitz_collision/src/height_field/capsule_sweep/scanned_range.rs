//! 掃引の走査が調べた範囲: 覆いの升目をすべて調べ切れたかどうかを表す。答えが確定的かどうかの軸である。
//!
//! 線分の走査が持つ同名の軸と別の型にするのは、確定性を保つ理由が違うからである。線分の走査は升目を時刻の
//! 順に辿れるため、答えられない升目に達した時点で止めれば、見つけた当たりより手前をすべて調べ終えている。
//! 掃引の覆いは面であり時刻の順に並べられないため、覆いの中に答えられない升目が1つでもあれば、その升目に
//! もっと早い接触がありうる。したがって掃引は、見つけた接触を捨てて打ち切りの側で答える。
//! どちらも「確定した接触とその手前の未評価が同時に立つ答えは作れない」という同じ性質へ至るが、
//! 至る道が違うため、2つの型がそれぞれの理由を持つ。

/// 掃引の走査が覆いの升目をすべて調べ切れたか。接触の有無の答えが確定的かどうかの軸である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[allow(missing_docs)] // 枝の説明は型の`///`が持つ。枝ごとの`///`は宣言の間のコメント行になり規約に反する
pub enum 掃引の走査が調べた範囲 {
    覆いの升目をすべて調べた,     // 覆いの中の升目をすべて調べ切ったため、接触の有無は確定している
    調べられない升目で打ち切った, // 四隅の高さを答えられない升目が覆いの中にあり、答えは確定していない
}
