//! 接触の特徴の候補: カプセルのどの部分が三角形のどの特徴に触れるかの組み合わせである。
//! 掃引の求解は、8種類を数え上げた20通りの候補を1つずつ数え、それぞれの接触の時刻を解いて最小を選ぶ。
//!
//! 8種類で足りる根拠は、最初に触れた瞬間の最近接点の対にある。カプセル側の最近接点は軸の2つの端か軸の内側の
//! どれかであり、三角形側の最近接点は面の内側か3辺の内側か3頂点のどれかである。種類の組み合わせは9つだが、
//! 軸の内側が面の内側に触れる場合は軸が面と平行であり、そのとき軸の端も同じ時刻に同じ隔たりへ達するか、
//! 軸の水平の投影が三角形の辺をまたぐため辺の候補が同じ時刻を答える。したがって軸の内側と面の組を数えない。
//!
//! どの候補も、平面・直線という三角形やカプセルより広がった形での接触を解くため、根の時刻で媒介変数が
//! 三角形と軸の範囲に収まることを確かめる。収まる根はどれも実際に触れている時刻であるから、最初に触れる
//! 時刻より早くはなりえない。したがって候補ごとに範囲を満たす最小の根を取り、その最小を選べば答えになる。
//!
//! 辺と頂点を指す並びの位置は、`升目の地表の三角形`が並べた3つの頂点の中の位置である。辺は、その位置の
//! 頂点から次の位置の頂点へ張ったものを指す。

use crate::solver::軸の端;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 接触の特徴の候補 {
    面と軸の端 { 端: 軸の端 },
    辺と軸の端 { 端: 軸の端, 辺の並びの位置: usize },
    頂点と軸の端 { 端: 軸の端, 頂点の並びの位置: usize },
    辺と軸の内側 { 辺の並びの位置: usize },
    頂点と軸の内側 { 頂点の並びの位置: usize },
}

impl 接触の特徴の候補 {
    // 20通りの候補を、求解が数える順に並べる。並びを固定するのは、接触の時刻が並んだときにどの特徴の
    // 答えを返すかまで入力だけで決まるようにするためである。
    pub(super) fn 並べる() -> impl Iterator<Item = Self> {
        let 軸の端ごと = 軸の端::並べる().into_iter().flat_map(|端| {
            let 面 = [Self::面と軸の端 { 端 }].into_iter();
            面.chain((0..3).flat_map(move |位置| {
                [
                    Self::辺と軸の端 {
                        端, 辺の並びの位置: 位置
                    },
                    Self::頂点と軸の端 {
                        端, 頂点の並びの位置: 位置
                    },
                ]
            }))
        });
        軸の端ごと.chain((0..3).flat_map(|位置| {
            [
                Self::辺と軸の内側 {
                    辺の並びの位置: 位置
                },
                Self::頂点と軸の内側 {
                    頂点の並びの位置: 位置
                },
            ]
        }))
    }
}
