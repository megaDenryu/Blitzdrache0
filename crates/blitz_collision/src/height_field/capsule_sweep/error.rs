//! カプセルの掃引の問い合わせで破れる条件。掃引は升目ごとに区分線形の面と三角形の頂点を組み直すため、
//! 升目の値の生成の破れと位置の生成の破れをこの語彙へ畳み込む。
//!
//! 覆いが高さ場の広がりの外へ出たことはここに入らない。それは値が壊れたのではなく、走査が覆いのどこまでを
//! 調べられたかの話であり、`掃引の走査が調べた範囲`が別の軸で表す。

use thiserror::Error;

use super::super::error::升目の値の生成エラー;
use super::super::position_error::高さ場の位置の生成エラー;
use crate::solver::無次元の媒介変数の生成エラー;

/// カプセルの掃引の問い合わせで破れる条件。半径が正の有限でないこと、半径が上限を越えていること、掃引で動けた割合が範囲外になること、掃引が触れる位置を作れないこと、調べる升目の値を作れないことの5つである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum カプセルの掃引の問い合わせエラー {
    /// 半径が0以下か、有限でない値だった。
    #[error("カプセルの半径が正の有限値でない")]
    カプセルの半径が正の有限値でない,
    /// 半径が、係数の桁あふれを避けるために課した長さの絶対値の上限を越えていた。
    #[error("カプセルの半径が受け付ける長さの絶対値の上限を越えている")]
    カプセルの半径が上限を越えている,
    /// 変位のうち動けた割合が、0以上1以下の有限値でなかった。
    #[error("掃引で動けた割合を作れない: {0}")]
    掃引で動けた割合を作れない(#[from] 無次元の媒介変数の生成エラー),
    /// 掃引が触れる点を高さ場の格子原点からの位置として作れなかった。
    #[error("カプセルの掃引が触れる位置を作れない: {0}")]
    掃引の位置を作れない(#[from] 高さ場の位置の生成エラー),
    /// 覆いの中の升目の四隅の高さや地表の面を値として作れなかった。
    #[error("カプセルの掃引が調べる升目の値を作れない: {0}")]
    升目の値を作れない(#[from] 升目の値の生成エラー),
}
