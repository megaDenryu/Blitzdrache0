//! 掃引の水平の覆い: カプセルの軸の水平投影を半径ぶん膨らませ、掃引の変位ぶん掃いた範囲を包む、
//! 升目の添字の軸平行の矩形である。接触しうる升目はこの矩形の中にしか無い。
//!
//! 線分の問い合わせが横断した升目だけを辿るのと方式が違うのは、掃引の覆いが線ではなく面だからである。
//! 面の中の升目を接触の時刻の順に並べる手立てが無いため、覆いの升目をすべて調べて最小の時刻を選ぶ。
//! 計算量は覆いの升目の数に比例する。キャラクターの1刻みの変位と半径は升目より小さいため、
//! 実際の覆いは数升目に収まる。
//!
//! 半径を水平の両側へ足すだけで足りるのは、カプセルが軸から半径以内の点の集合であり、その水平投影が
//! 軸の水平投影を半径ぶん膨らませた領域に等しいからである。

use super::super::cell_edge::升目の一辺;
use super::super::cell_index::升目の格子添字;
use super::super::real_cell_index::実数の床を升目の添字へ写す;
use super::capsule::高さ場を掃引するカプセル;

#[derive(Clone, Copy)]
pub(super) struct 掃引の水平の覆い {
    東の添字の始まり: i32,
    東の添字の終わり: i32,
    南の添字の始まり: i32,
    南の添字の終わり: i32,
}

impl 掃引の水平の覆い {
    /// 掃引を包む升目の矩形を求める。添字として表せない広がりになる入力は`None`を返し、
    /// 呼び出し側は調べられない升目に達したのと同じ打ち切りとして扱う。
    pub(super) fn カプセルの掃引から求める(
        カプセル: &高さ場を掃引するカプセル, 一辺: 升目の一辺<f64>
    ) -> Option<Self> {
        let 変位 = カプセル.掃引の変位();
        let 半径 = カプセル.半径のメートル();
        let 東の端 = カプセル.軸の端点を並べる().map(|端点| 端点.東のメートル());
        let 南の端 = カプセル.軸の端点を並べる().map(|端点| 端点.南のメートル());
        let (東の始まり, 東の終わり) = 軸ごとの覆いの添字を求める(東の端, 変位.東のメートル(), 半径, 一辺)?;
        let (南の始まり, 南の終わり) = 軸ごとの覆いの添字を求める(南の端, 変位.南のメートル(), 半径, 一辺)?;
        Some(Self {
            東の添字の始まり: 東の始まり,
            東の添字の終わり: 東の終わり,
            南の添字の始まり: 南の始まり,
            南の添字の終わり: 南の終わり,
        })
    }

    /// 覆いの升目を、南が外側・東が内側の昇順で並べる。並びを固定するのは、接触の時刻が並んだときに
    /// どの升目の答えを返すかまで入力だけで決まるようにするためである。
    pub(super) fn 升目を並べる(self) -> impl Iterator<Item = 升目の格子添字> {
        let 東の範囲 = self.東の添字の始まり..=self.東の添字の終わり;
        (self.南の添字の始まり..=self.南の添字の終わり)
            .flat_map(move |南添字| 東の範囲.clone().map(move |東添字| 升目の格子添字::生成する(東添字, 南添字)))
    }
}

/// 1つの軸について、覆いが跨ぐ升目の添字の下端と上端を求める。掃引の前後の2つの端点と半径で挟んだ
/// メートルの区間を、升目の添字へ写す。
fn 軸ごとの覆いの添字を求める(
    軸の端: [f64; 2], 変位の成分: f64, 半径: f64, 一辺: 升目の一辺<f64>
) -> Option<(i32, i32)> {
    let 掃引の前後 = [軸の端[0], 軸の端[1], 軸の端[0] + 変位の成分, 軸の端[1] + 変位の成分];
    let 下端 = 掃引の前後.into_iter().fold(f64::INFINITY, f64::min) - 半径;
    let 上端 = 掃引の前後.into_iter().fold(f64::NEG_INFINITY, f64::max) + 半径;
    let 始まり = 実数の床を升目の添字へ写す(一辺.メートルを実数添字へ直す(下端))?;
    let 終わり = 実数の床を升目の添字へ写す(一辺.メートルを実数添字へ直す(上端))?;
    Some((始まり, 終わり))
}
