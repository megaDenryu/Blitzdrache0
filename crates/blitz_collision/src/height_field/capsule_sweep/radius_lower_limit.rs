//! 高さ場を掃引するカプセルの半径が守る絶対値の下限。高さ場の問い合わせが受け付ける長さの絶対値の上限の
//! 逆数として定めるため、2のマイナス24乗メートルすなわちおよそ60ナノメートルである。
//!
//! 下限を課すのは、求解が作る半径の二乗が非正規化数へ落ちないことを保証するためである。非正規化数とは、
//! 指数がこれ以上小さくならないところで仮数の桁を削って表す値であり、その二乗はほとんどの場合0へ潰れる。
//! 下限をrと書くと半径の二乗はrの二乗すなわち2のマイナス48乗以上であり、倍精度の正規化数の最小が
//! 2のマイナス1022乗であるから、接触の隔たりが達すべき目標値は常に正規化数に収まる。目標値が0へ潰れると、
//! 地表から離れているカプセルの隔たりの二乗も同時に0へ落ちて、掃引の始まりから触れているものとして扱われる。
//!
//! カプセルどうしの接触が同じ下限を持つのは、半径の破れの意味が2つの問い合わせで同じであり、値が食い違うと
//! 同じ半径が片方の問い合わせでだけ拒まれるためである。値はどちらもそれぞれの上限の逆数として導いており、
//! 2つの上限が同じ2の24乗メートルであることからここでも同じ値になる。
//! 参照: `crates/blitz_collision/src/shape/capsule_radius_lower_limit.rs`
//!
//! 上限とその算術は `crates/blitz_collision/src/height_field/length_limit.rs` にある。

