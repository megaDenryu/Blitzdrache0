//! 軸と辺の最近接の媒介変数: ねじれの位置にある2つの直線が最も近づく点を、それぞれの直線の上の比で表したものである。
//! 軸の比は軸の始点を0・終点を1、辺の比は辺の始点を0・終点を1として測る。
//!
//! 2つの比を裸の実数の対で持ち回すと、どちらがどちらの直線の比かを署名が語らなくなるためこの型で包む。
//! 求め方は、隔たりの二乗を2つの比の2次式とみて偏微分を0に置いた連立1次方程式であり、その行列式は
//! 2つの変位の外積の長さの二乗である。平行な2直線では0になり、最近接点が1組に定まらない。

use super::super::grid_origin_displacement::高さ場の中の変位;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 軸と辺の最近接の媒介変数 {
    軸の比: f64,
    辺の比: f64,
}

impl 軸と辺の最近接の媒介変数 {
    /// 2つの比を求め、どちらもそれぞれの範囲(0以上1以下)に収まる場合だけ返す。平行な2直線と、
    /// 長さ0の変位では最近接点が定まらないため`None`を返す。
    pub(super) fn 求める(
        軸: 高さ場の中の変位, 辺: 高さ場の中の変位, 辺の始点から軸の始点へ: 高さ場の中の変位
    ) -> Option<Self> {
        let 行列式 = 軸.外積(辺).長さの二乗();
        if 行列式 <= 0.0 {
            return None;
        }
        let 軸の長さの二乗 = 軸.長さの二乗();
        let 辺の長さの二乗 = 辺.長さの二乗();
        let 軸と辺の内積 = 軸.内積(辺);
        let 軸への射影 = 辺の始点から軸の始点へ.内積(軸);
        let 辺への射影 = 辺の始点から軸の始点へ.内積(辺);
        let 軸の比 = (軸と辺の内積 * 辺への射影 - 辺の長さの二乗 * 軸への射影) / 行列式;
        let 辺の比 = (軸の長さの二乗 * 辺への射影 - 軸と辺の内積 * 軸への射影) / 行列式;
        if !(0.0..=1.0).contains(&軸の比) || !(0.0..=1.0).contains(&辺の比) {
            return None;
        }
        Some(Self { 軸の比, 辺の比 })
    }

    pub(super) fn 軸の比(&self) -> f64 {
        self.軸の比
    }

    pub(super) fn 辺の比(&self) -> f64 {
        self.辺の比
    }
}
