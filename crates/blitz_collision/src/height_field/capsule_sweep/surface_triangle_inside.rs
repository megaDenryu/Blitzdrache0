//! 三角形の平面の上の点が、三角形の内側(辺の上を含む)にあるかの判定。触れるのは3つの頂点の位置だけである。
//!
//! 3辺それぞれについて、辺の変位と辺の始点から点への変位の外積を取り、3つがすべて同じ側を向いていれば内側である。
//! 向きの基準に上向きの単位法線を使わず、3頂点の並びから組んだ外積を使うのは、2つの三角形で頂点の並びの
//! 巻き方向が揃っていないためである。基準を並びから組めば、巻き方向がどちらでも3つの符号が揃う。

use super::super::grid_origin_position::高さ場の格子原点からの位置;
use super::surface_triangle::升目の地表の三角形;

impl 升目の地表の三角形 {
    pub(super) fn 面の上の点が内側にあるか(&self, 点: 高さ場の格子原点からの位置) -> bool {
        let 第1の辺 = self.頂点の位置(0).終点までの変位を求める(self.頂点の位置(1));
        let 第2の辺 = self.頂点の位置(0).終点までの変位を求める(self.頂点の位置(2));
        let 並びから組んだ向き = 第1の辺.外積(第2の辺);
        (0..3).all(|辺の並びの位置| {
            let 始点 = self.頂点の位置(辺の並びの位置);
            let 辺 = 始点.終点までの変位を求める(self.頂点の位置(辺の並びの位置 + 1));
            let 始点から点へ = 始点.終点までの変位を求める(点);
            辺.外積(始点から点へ).内積(並びから組んだ向き) >= 0.0
        })
    }
}
