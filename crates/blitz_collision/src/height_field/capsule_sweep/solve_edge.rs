//! 三角形の辺と軸の端の接触、および辺に触れた最近接の組み立て。
//!
//! 半径の球が辺の直線へ達する条件は、中心から直線までの隔たりが半径に等しいことである。その隔たりの二乗は
//! 「辺の始点から中心への変位と辺の変位の外積」の長さの二乗を辺の長さの二乗で割ったものであるから、
//! 分母を払うと時刻の2次方程式になる。直線は辺より長いため、根の時刻で最近接点が辺の内側に収まることを確かめる。
//! 収まらない接触は、辺の端すなわち三角形の頂点の候補が答える。

use super::super::grid_origin_displacement::高さ場の中の変位;
use super::axis_end::軸の端;
use super::contact_candidate::軸と特徴の最近接;
use super::contact_place::触れた場所;
use super::contact_solver::カプセルと三角形の接触の求解;
use super::error::カプセルの掃引の問い合わせエラー;
use super::feature::地表に触れた特徴;
use super::quadratic::掃引の2次方程式;

impl カプセルと三角形の接触の求解<'_> {
    pub(super) fn 辺と軸の端の方程式を組む(&self, 端: 軸の端, 辺の並びの位置: usize) -> Option<掃引の2次方程式> {
        let 辺 = self.辺の変位(辺の並びの位置);
        let 辺の長さの二乗 = 辺.長さの二乗();
        if 辺の長さの二乗 <= 0.0 {
            return None;
        }
        let 始まりの外積 = self.頂点から時刻の軸の端への変位(辺の並びの位置, 端, 0.0).外積(辺);
        let 速度の外積 = self.掃引の変位().外積(辺);
        Some(掃引の2次方程式::生成する(
            速度の外積.長さの二乗(),
            2.0 * 速度の外積.内積(始まりの外積),
            始まりの外積.長さの二乗() - self.半径の二乗() * 辺の長さの二乗,
        ))
    }

    // 時刻での、辺の直線と軸の端の最近接。最近接点が辺の外にあるなら`None`を返す。
    pub(super) fn 辺と軸の端の最近接を求める(
        &self,
        端: 軸の端,
        辺の並びの位置: usize,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, カプセルの掃引の問い合わせエラー> {
        let 辺 = self.辺の変位(辺の並びの位置);
        let 辺の長さの二乗 = 辺.長さの二乗();
        if 辺の長さの二乗 <= 0.0 {
            return Ok(None);
        }
        let 辺の始点から軸へ = self.頂点から時刻の軸の端への変位(辺の並びの位置, 端, 時刻);
        let 辺の比 = 辺の始点から軸へ.内積(辺) / 辺の長さの二乗;
        if !(0.0..=1.0).contains(&辺の比) {
            return Ok(None);
        }
        let 接触点から軸へ = 辺の始点から軸へ.引く(辺.実数倍する(辺の比));
        Ok(Some(self.辺に触れた最近接を組む(辺の並びの位置, 辺の比, 接触点から軸へ)?))
    }

    // 辺の上の1点に触れた最近接を組む。接触位置は辺の始点から辺の変位を比の分だけ進めた点である。
    pub(super) fn 辺に触れた最近接を組む(
        &self,
        辺の並びの位置: usize,
        辺の比: f64,
        接触点から軸へ: 高さ場の中の変位,
    ) -> Result<軸と特徴の最近接, カプセルの掃引の問い合わせエラー> {
        let 接触位置 = self
            .三角形()
            .頂点の位置(辺の並びの位置)
            .変位だけ進んだ位置を求める(self.辺の変位(辺の並びの位置).実数倍する(辺の比))?;
        Ok(軸と特徴の最近接::生成する(
            接触点から軸へ.長さの二乗(),
            触れた場所::生成する(
                接触位置,
                self.接触の単位法線を正す(接触点から軸へ),
                地表に触れた特徴::三角形の辺 {
                    始まりの隅: self.三角形().頂点の隅(辺の並びの位置),
                    終わりの隅: self.三角形().頂点の隅(辺の並びの位置 + 1),
                },
            ),
        ))
    }
}
