//! 三角形の頂点と、軸の端および軸の内側の接触。
//!
//! 軸の端との接触は、半径の球が固定の点へ達する条件であるから、中心と点の隔たりの二乗が半径の二乗に等しい
//! という2次方程式になる。制約は無い。球はカプセルの一部であるから、この根はどれも実際に触れている時刻である。
//!
//! 軸の内側との接触は、頂点から軸の直線までの隔たりが半径に等しい条件である。隔たりの二乗は
//! 「頂点から軸の始点への変位と軸の変位の外積」の長さの二乗を軸の長さの二乗で割ったものであるから、
//! 分母を払うと2次方程式になる。直線は軸より長いため、根の時刻で最近接点が軸の内側に収まることを確かめる。

use super::super::grid_origin_displacement::高さ場の中の変位;
use super::axis_end::軸の端;
use super::contact_candidate::軸と特徴の最近接;
use super::contact_place::触れた場所;
use super::contact_solver::カプセルと三角形の接触の求解;
use super::error::カプセルの掃引の問い合わせエラー;
use super::feature::地表に触れた特徴;
use super::quadratic::掃引の2次方程式;

impl カプセルと三角形の接触の求解<'_> {
    pub(super) fn 頂点と軸の端の方程式を組む(&self, 端: 軸の端, 頂点の並びの位置: usize) -> 掃引の2次方程式 {
        let 始まりの変位 = self.頂点から時刻の軸の端への変位(頂点の並びの位置, 端, 0.0);
        let 速度 = self.掃引の変位();
        掃引の2次方程式::生成する(
            速度.長さの二乗(),
            2.0 * 始まりの変位.内積(速度),
            始まりの変位.長さの二乗() - self.半径の二乗(),
        )
    }

    pub(super) fn 頂点と軸の端の最近接を求める(
        &self,
        端: 軸の端,
        頂点の並びの位置: usize,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, カプセルの掃引の問い合わせエラー> {
        let 頂点から軸へ = self.頂点から時刻の軸の端への変位(頂点の並びの位置, 端, 時刻);
        Ok(Some(self.頂点に触れた最近接を組む(頂点の並びの位置, 頂点から軸へ)))
    }

    // 軸の内側と頂点の方程式。軸の長さが0のカプセル(球)には内側が無いため`None`を返す。
    pub(super) fn 頂点と軸の内側の方程式を組む(&self, 頂点の並びの位置: usize) -> Option<掃引の2次方程式> {
        let 軸 = self.軸の変位();
        let 軸の長さの二乗 = 軸.長さの二乗();
        if 軸の長さの二乗 <= 0.0 {
            return None;
        }
        let 始まりの外積 = self.頂点から時刻の軸の端への変位(頂点の並びの位置, 軸の端::始点の側, 0.0).外積(軸);
        let 速度の外積 = self.掃引の変位().外積(軸);
        Some(掃引の2次方程式::生成する(
            速度の外積.長さの二乗(),
            2.0 * 速度の外積.内積(始まりの外積),
            始まりの外積.長さの二乗() - self.半径の二乗() * 軸の長さの二乗,
        ))
    }

    // 時刻での、頂点と軸の直線の最近接。最近接点が軸の外にあるなら、その接触は軸の端の候補が答えるため
    // `None`を返す。
    pub(super) fn 頂点と軸の内側の最近接を求める(
        &self,
        頂点の並びの位置: usize,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, カプセルの掃引の問い合わせエラー> {
        let 軸 = self.軸の変位();
        let 軸の長さの二乗 = 軸.長さの二乗();
        if 軸の長さの二乗 <= 0.0 {
            return Ok(None);
        }
        let 頂点から始点へ = self.頂点から時刻の軸の端への変位(頂点の並びの位置, 軸の端::始点の側, 時刻);
        let 軸の比 = -頂点から始点へ.内積(軸) / 軸の長さの二乗;
        if !(0.0..=1.0).contains(&軸の比) {
            return Ok(None);
        }
        let 頂点から軸へ = 頂点から始点へ.加える(軸.実数倍する(軸の比));
        Ok(Some(self.頂点に触れた最近接を組む(頂点の並びの位置, 頂点から軸へ)))
    }

    fn 頂点に触れた最近接を組む(
        &self, 頂点の並びの位置: usize, 頂点から軸へ: 高さ場の中の変位
    ) -> 軸と特徴の最近接 {
        軸と特徴の最近接::生成する(
            頂点から軸へ.長さの二乗(),
            触れた場所::生成する(
                self.三角形().頂点の位置(頂点の並びの位置),
                self.接触の単位法線を正す(頂点から軸へ),
                地表に触れた特徴::三角形の頂点(self.三角形().頂点の隅(頂点の並びの位置)),
            ),
        )
    }
}
