//! 候補の種類から、その特徴の方程式と最近接の工程を選ぶ振り分け。担当するのは選ぶことだけであり、
//! 式そのものは面・辺・頂点の3つの求解が持つ。
//!
//! 振り分けを1箇所へ集めるのは、候補の種類を増やしたときに方程式と最近接の片方だけを足す取りこぼしを
//! 型検査で落とすためである。網羅の`match`が2つ並ぶため、枝を1つ足すと両方が同時にコンパイルで失敗する。

use super::candidate::接触の特徴の候補;
use super::contact_candidate::軸と特徴の最近接;
use super::contact_solver::カプセルと三角形の接触の求解;
use super::error::カプセルの掃引の問い合わせエラー;
use crate::solver::掃引の2次方程式;

impl カプセルと三角形の接触の求解<'_> {
    // 候補の接触の時刻が満たす方程式。その候補が成り立たない形(長さ0の軸・平行な2直線)では`None`を返す。
    pub(super) fn 候補の方程式を組む(&self, 候補: 接触の特徴の候補) -> Option<掃引の2次方程式> {
        match 候補 {
            接触の特徴の候補::面と軸の端 { 端 } => Some(self.面と軸の端の方程式を組む(端)),
            接触の特徴の候補::辺と軸の端 { 端, 辺の並びの位置 } => self.辺と軸の端の方程式を組む(端, 辺の並びの位置),
            接触の特徴の候補::頂点と軸の端 {
                端, 頂点の並びの位置
            } => Some(self.頂点と軸の端の方程式を組む(端, 頂点の並びの位置)),
            接触の特徴の候補::辺と軸の内側 { 辺の並びの位置 } => self.辺と軸の内側の方程式を組む(辺の並びの位置),
            接触の特徴の候補::頂点と軸の内側 { 頂点の並びの位置 } => {
                self.頂点と軸の内側の方程式を組む(頂点の並びの位置)
            }
        }
    }

    // 時刻での、その候補が指す特徴とカプセルの最近接。媒介変数が三角形と軸の範囲の外にあるなら`None`を返す。
    pub(super) fn 候補の最近接を求める(
        &self,
        候補: 接触の特徴の候補,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, カプセルの掃引の問い合わせエラー> {
        match 候補 {
            接触の特徴の候補::面と軸の端 { 端 } => self.面と軸の端の最近接を求める(端, 時刻),
            接触の特徴の候補::辺と軸の端 { 端, 辺の並びの位置 } => {
                self.辺と軸の端の最近接を求める(端, 辺の並びの位置, 時刻)
            }
            接触の特徴の候補::頂点と軸の端 {
                端, 頂点の並びの位置
            } => self.頂点と軸の端の最近接を求める(端, 頂点の並びの位置, 時刻),
            接触の特徴の候補::辺と軸の内側 { 辺の並びの位置 } => {
                self.辺と軸の内側の最近接を求める(辺の並びの位置, 時刻)
            }
            接触の特徴の候補::頂点と軸の内側 { 頂点の並びの位置 } => {
                self.頂点と軸の内側の最近接を求める(頂点の並びの位置, 時刻)
            }
        }
    }
}
