//! 升目の一辺: 高さの標本が並ぶ刻みのメートルである。
//!
//! 高さの差を傾きへ直す割り算をこの型が持つのは、傾きの定義(1メートル進むときに何メートル上がるか)が
//! 一辺の長さに属するためである。割る相手を呼び出し側に持たせると、刻みの違う格子の値で割る誤りが署名の上で書ける。

use super::error::升目の値の生成エラー;
use super::real::地表の平面の実数;

/// 升目の一辺。高さの標本が並ぶ刻みのメートルである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 升目の一辺<数>(数);

impl<数: 地表の平面の実数> 升目の一辺<数> {
    /// 正の有限値だけを受け付ける。
    pub fn 生成する(メートル: 数) -> Result<Self, 升目の値の生成エラー> {
        if !メートル.有限か() || メートル <= 数::零() {
            return Err(升目の値の生成エラー::升目の一辺が正の有限値でない);
        }
        Ok(Self(メートル))
    }

    /// 一辺の両端の高さの差を、1メートルあたりの高さの変化へ直す。
    pub fn 高さの差を傾きへ直す(&self, 高さの差: 数) -> 数 {
        高さの差 / self.0
    }

    /// 格子原点から測ったメートルを、升目の何個ぶんかを表す実数の添字へ直す。整数部が升目の添字、
    /// 小数部が升目の中の比になる。割り算そのものは高さの差を傾きへ直すのと同じだが、割られる量も
    /// 割った結果の意味も別であるため、別のメソッドとして持つ。
    pub fn メートルを実数添字へ直す(&self, メートル: 数) -> 数 {
        メートル / self.0
    }

    /// 升目の何個ぶんかを表す実数添字を、格子原点から測ったメートルへ直す。格子点の位置を組むときに使う。
    pub fn 実数添字をメートルへ直す(&self, 実数添字: 数) -> 数 {
        実数添字 * self.0
    }
}
