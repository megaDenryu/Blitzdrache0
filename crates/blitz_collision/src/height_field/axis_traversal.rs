//! 東または南の1つの軸について、線分が升目の境界へ達する時刻と、今どの升目の列に居るかを持つ工程。
//! 東と南でまったく同じ計算をするため、軸を1つだけ知る型としてここへ置く。
//! 触れるのは自分の始点の実数添字・速度・現在の升目の添字の3つだけである。

use super::linear_in_parameter::媒介変数の1次式;

/// 升目の添字の絶対値の上限。2の30乗であり、高さ場の格子点数の上限(65535)を大きく上回る。
/// この範囲に収まる床の整数は32ビット符号付き整数へ必ず収まり、隣へ1つ進む加算も溢れない。
const 升目の添字の絶対値の上限: f64 = 1_073_741_824.0;

#[derive(Clone, Copy)]
pub(super) struct 軸ごとの升目の横断 {
    始点の実数添字: f64,
    実数添字の速度: f64,
    現在の升目の添字: i32,
}

impl 軸ごとの升目の横断 {
    /// 両端の実数添字から作る。どちらかが升目の添字として表せない範囲にあれば`None`を返す。
    /// 終点まで検査するのは、走査が進む升目の数がこの2つの差で決まるためである。
    pub(super) fn 生成する(始点の実数添字: f64, 終点の実数添字: f64) -> Option<Self> {
        実数の床を升目の添字へ写す(終点の実数添字)?;
        let 始点の床 = 実数の床を升目の添字へ写す(始点の実数添字)?;
        let 実数添字の速度 = 終点の実数添字 - 始点の実数添字;
        // 升目の境界のちょうど上から負の向きへ進むときは、1つ手前の升目に居るものとして扱う。
        // そうしないと、始点の升目が幅0の区間になり、線分が一度も通らない升目を1つ余計に尋ねることになる。
        let 境界の上から手前へ進む = 実数添字の速度 < 0.0 && 始点の実数添字 == 始点の実数添字.floor();
        let 現在の升目の添字 = if 境界の上から手前へ進む {
            始点の床.checked_sub(1)?
        } else {
            始点の床
        };
        Some(Self {
            始点の実数添字,
            実数添字の速度,
            現在の升目の添字,
        })
    }

    pub(super) fn 現在の升目の添字(&self) -> i32 {
        self.現在の升目の添字
    }

    /// 升目の境界のちょうど上に静止しているか。この軸へ進まない線分の始点が境界に載っている場合であり、
    /// その点は境界の両側の升目のどちらにも属する。負の向きへ進む線分を1つ手前へ寄せる上の規約は、
    /// 手前の升目でなければ線分が通る区間が幅0になるという理由で片方を選べたが、静止した軸にはその理由が無く、
    /// 両側が等しく正しい。どちらの升目が格子に実在するかは格子の広がりを持つ供給元しか知らないため、
    /// 走査の始まりを選ぶ側がこの問いを使って供給元へ尋ねる。
    pub(super) fn 境界の上に静止しているか(&self) -> bool {
        self.実数添字の速度 == 0.0 && self.始点の実数添字 == self.始点の実数添字.floor()
    }

    /// 走査の始まりとして在りうる横断を、選ぶ順に並べる。境界の上に静止した軸だけが2つ目を持つ。
    /// 床の側を先に並べるため、両側とも実在する内部の境界では床の側が選ばれ、これまでの選び方が変わらない。
    pub(super) fn 走査の始まりに在りうる横断を並べる(&self) -> impl Iterator<Item = Self> {
        [Some(*self), self.手前の升目に居るものとして数え直す()].into_iter().flatten()
    }

    /// 境界の上に静止した軸を、1つ手前の升目に居るものとして数え直す。静止していない軸と、
    /// 添字が表せる範囲を出る場合は`None`を返す。
    fn 手前の升目に居るものとして数え直す(&self) -> Option<Self> {
        if !self.境界の上に静止しているか() {
            return None;
        }
        Some(Self {
            現在の升目の添字: self.現在の升目の添字.checked_sub(1)?,
            ..*self
        })
    }

    /// 次に升目の境界へ達する時刻。この軸へ進まない線分では無限大を返し、境界へ永久に達しないことを表す。
    pub(super) fn 次に境界へ達する時刻(&self) -> f64 {
        if self.実数添字の速度 == 0.0 {
            return f64::INFINITY;
        }
        let 境界の添字 = if self.実数添字の速度 > 0.0 {
            self.現在の升目の添字.saturating_add(1)
        } else {
            self.現在の升目の添字
        };
        (f64::from(境界の添字) - self.始点の実数添字) / self.実数添字の速度
    }

    /// 境界を1つ越えて隣の升目へ移る。添字が表せる範囲を出るなら`None`を返し、走査はそこで打ち切られる。
    pub(super) fn 隣の升目へ移る(&mut self) -> Option<()> {
        let 進む向き = if self.実数添字の速度 > 0.0 { 1 } else { -1 };
        self.現在の升目の添字 = self.現在の升目の添字.checked_add(進む向き)?;
        Some(())
    }

    /// 現在の升目の中の比を、線分の媒介変数の1次式として表したもの。升目が変わると基準の添字が変わるため、
    /// 升目ごとに求め直す。
    pub(super) fn 現在の升目の中の比の1次式(&self) -> 媒介変数の1次式 {
        媒介変数の1次式::生成する(self.始点の実数添字 - f64::from(self.現在の升目の添字), self.実数添字の速度)
    }
}

/// 非負にも負にもなる実数の格子座標から、それを含む升目の添字を求める。
/// 数値のasキャストをワークスペースが禁じており、実数から整数への切り捨てを行う安全な変換が標準に無いため、
/// ビットの重みを大きい側から差し引いて絶対値を組み立て、符号を後から付ける。
/// 参照: `crates/blitz_engine/src/height_field/grid_index.rs`の非負向けの同型の変換
fn 実数の床を升目の添字へ写す(実数添字: f64) -> Option<i32> {
    if !実数添字.is_finite() {
        return None;
    }
    let 床 = 実数添字.floor();
    if !(-升目の添字の絶対値の上限..升目の添字の絶対値の上限).contains(&床) {
        return None;
    }
    let mut 残り = 床.abs();
    let mut 絶対値 = 0_u32;
    for ビット in (0_u32..31).rev() {
        let 重み = 1_u32 << ビット;
        if 残り >= f64::from(重み) {
            絶対値 |= 重み;
            残り -= f64::from(重み);
        }
    }
    let 整数 = i32::try_from(絶対値).ok()?;
    Some(if 床 < 0.0 { -整数 } else { 整数 })
}
