//! 走査の向きと格子の縁の扱いの反証。東と南の添字が減る向きへ進む線分、升目の境界のちょうど上から
//! 手前の升目へ進む線分、2つの軸の境界へ同時に達して升目の角を通る線分、格子のいちばん外の縁と角の上を
//! 垂直に落ちる線分の5つを見る。
//!
//! 境界の上から負の向きへ進む場合を分けて見るのは、実数添字の床がそのままでは線分が一度も通らない
//! 升目を指すためである。角の通過を分けて見るのは、片方の軸だけ隣へ移すと、線分が実際には通っていない
//! 升目を1つ調べて別の升目を飛ばすためである。格子のいちばん外の縁を分けて見るのは、床がそのままでは
//! 格子に実在しない升目を指し、線分が縁の上に在るのに打ち切りになるためである。

#![allow(clippy::unwrap_used)]

use super::segment_query_fixture::{位置, 平らな地形を作る, 当たりを取り出す, 当たりを求める};
use super::{升目の三角形, 線分の走査が調べた範囲};

/// 東1.75メートルから0.25メートルへ、添字が減る向きへ進みながら高さ1メートルから-3メートルへ降りる線分。
/// 地表(高さ0メートル)へ達するのは4メートル落ちる間に1メートルぶん降りた時点であり、交差時刻は0.25である。
#[test]
fn 添字が減る向きへ進む線分も正しく当たる() {
    let 結果 = 当たりを求める(&平らな地形を作る(), 1.0, 位置(1.75, 1.0, 0.75), 位置(0.25, -3.0, 0.75));
    assert_eq!(結果.調べた範囲(), 線分の走査が調べた範囲::線分の全体を調べた);
    let 当たり = 当たりを取り出す(結果);
    assert_eq!(当たり.交差時刻().値(), 0.25);
    assert_eq!(当たり.交差位置(), 位置(1.375, 0.0, 0.75));
    assert_eq!(当たり.升目の添字().東添字(), 1);
}

/// 始点の東が格子のいちばん東の縁(2.0メートル)にあり、そこから西へ進む線分。実数添字の床をそのまま使うと
/// 升目2を指すが、升目2は格子の外であり、線分はそこを一度も通らない。調べた範囲が線分の全体であることが、
/// 通らない升目を尋ねて打ち切っていないことの反証である。
#[test]
fn 格子の縁から手前へ進む線分は手前の升目に入る() {
    let 結果 = 当たりを求める(&平らな地形を作る(), 1.0, 位置(2.0, 1.0, 0.75), 位置(1.0, -1.0, 0.75));
    assert_eq!(結果.調べた範囲(), 線分の走査が調べた範囲::線分の全体を調べた);
    let 当たり = 当たりを取り出す(結果);
    assert_eq!(当たり.交差時刻().値(), 0.5);
    assert_eq!(当たり.交差位置(), 位置(1.5, 0.0, 0.75));
    assert_eq!(当たり.升目の添字().東添字(), 1);
    assert_eq!(当たり.升目の添字().南添字(), 0);
}

/// 東と南が同じ速さで進む線分は、升目(0, 0)の右奥の角をちょうど通って升目(1, 1)へ入る。
/// 東と南の境界へ達する時刻がどちらも同じ商になる入力を選んでいる。商が食い違う入力では走査が角に触れるだけの
/// 脇の升目を1つ経由するが、答えは変わらない(`cell_traversal.rs`)。ここで見るのは、時刻が一致したときに
/// 片方の軸だけ隣へ移して升目を1つ飛ばすことがないことである。
/// 高さ3メートルから-1メートルへ4メートル落ちる間に3メートルぶん降りた時点が地表であり、交差時刻は0.75である。
/// その時点で東も南も1.25メートルであるから、当たる升目は(1, 1)である。
#[test]
fn 升目の角を通る線分は両方の軸で隣の升目へ移る() {
    let 結果 = 当たりを求める(&平らな地形を作る(), 1.0, 位置(0.5, 3.0, 0.5), 位置(1.5, -1.0, 1.5));
    assert_eq!(結果.調べた範囲(), 線分の走査が調べた範囲::線分の全体を調べた);
    let 当たり = 当たりを取り出す(結果);
    assert_eq!(当たり.交差時刻().値(), 0.75);
    assert_eq!(当たり.交差位置(), 位置(1.25, 0.0, 1.25));
    assert_eq!(当たり.升目の添字().東添字(), 1);
    assert_eq!(当たり.升目の添字().南添字(), 1);
    assert_eq!(当たり.地表の面().三角形(), 升目の三角形::奥側);
}

/// 東が格子のいちばん東の縁(2.0メートル)にあり、その縁の上を垂直に落ちる線分。東へは進まないため実数添字の
/// 床は升目2を指すが、3点かける3点の格子に升目2は無く、線分は実在する升目1の東の縁の上に在る。
/// 当たりが返ることが、境界の上に静止した軸を答えられる升目へ寄せている反証である。
#[test]
fn 格子の最大の縁の上を垂直に落ちる線分も当たる() {
    let 結果 = 当たりを求める(&平らな地形を作る(), 1.0, 位置(2.0, 1.0, 0.5), 位置(2.0, -1.0, 0.5));
    assert_eq!(結果.調べた範囲(), 線分の走査が調べた範囲::線分の全体を調べた);
    let 当たり = 当たりを取り出す(結果);
    assert_eq!(当たり.交差時刻().値(), 0.5);
    assert_eq!(当たり.交差位置(), 位置(2.0, 0.0, 0.5));
    assert_eq!(当たり.升目の添字().東添字(), 1);
    assert_eq!(当たり.升目の添字().南添字(), 0);
}

