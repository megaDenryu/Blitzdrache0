//! 升目の横断と三角形の選び方の反証。四隅が同一平面に乗らない鞍型の升目で双一次なら誤る位置に当たること、
//! 対角の両側で当たる三角形が切り替わること、複数の升目を横断してから当たること、
//! 格子の広がりの外へ出た走査が打ち切りを別の軸で伝えることを見る。
//! 境目とちょうど重なる線分は`segment_boundary_tests.rs`が持つ。

#![allow(clippy::unwrap_used)]

use super::segment_query_fixture::{
    位置, 平らな地形を作る, 当たりを取り出す, 当たりを求める, 検査用の四隅の供給元, 鞍型の地形を作る
};
use super::{升目の三角形, 線分が地表に最初に当たる点, 線分の走査が調べた範囲};

/// 東の比0.25・南の比0.75の点は奥側の三角形にあり、その平面の高さは0.5メートルである。
/// 同じ点を双一次で混ぜると0.625メートルになり、そこへ落ちる線分は交差時刻0.1875で当たる。
/// 交差時刻が0.25であることが、双一次でなく描画が張る三角形の平面へ当てている反証である。
#[test]
fn 鞍型の升目の奥側では双一次と違う高さで当たる() {
    let 当たり = 当たりを取り出す(当たりを求める(
        &鞍型の地形を作る(),
        1.0,
        位置(0.25, 1.0, 0.75),
        位置(0.25, -1.0, 0.75),
    ));
    assert_eq!(当たり.交差時刻().値(), 0.25);
    assert_eq!(当たり.交差位置(), 位置(0.25, 0.5, 0.75));
    assert_eq!(当たり.地表の面().三角形(), 升目の三角形::奥側);
}

/// 対角の手前側(東の比0.75・南の比0.25)でも平面の高さは0.5メートルだが、乗っている三角形は手前側である。
#[test]
fn 対角の手前側では手前側の三角形で当たる() {
    let 当たり = 当たりを取り出す(当たりを求める(
        &鞍型の地形を作る(),
        1.0,
        位置(0.75, 1.0, 0.25),
        位置(0.75, -1.0, 0.25),
    ));
    assert_eq!(当たり.交差時刻().値(), 0.25);
    assert_eq!(当たり.交差位置(), 位置(0.75, 0.5, 0.25));
    assert_eq!(当たり.地表の面().三角形(), 升目の三角形::手前側);
}

/// 東へ4点・南へ2点の地形。東添字0と1の高さは0メートル、東添字2と3の高さは4メートルであり、
/// 升目(1, 0)だけが東へ1メートルにつき4メートル上がる坂になる。
fn 途中に坂がある地形を作る() -> 検査用の四隅の供給元 {
    検査用の四隅の供給元::生成する(4, 2, vec![0.0, 0.0, 4.0, 4.0, 0.0, 0.0, 4.0, 4.0])
}

/// 高さ1メートルを保つ線分は、平らな升目(0, 0)を素通りしてから坂の升目(1, 0)で地表へ当たる。
/// 坂の高さが1メートルになるのは東1.25メートルの位置(升目の中の東の比0.25)であり、
/// 東0.25から2.25メートルへ2メートル進む線分ではその位置が中点にあたる。
#[test]
fn 複数の升目を横断してから当たる() {
    let 結果 = 当たりを求める(&途中に坂がある地形を作る(), 1.0, 位置(0.25, 1.0, 0.5), 位置(2.25, 1.0, 0.5));
    assert_eq!(結果.調べた範囲(), 線分の走査が調べた範囲::線分の全体を調べた);
    let 当たり = 当たりを取り出す(結果);
    assert_eq!(当たり.交差時刻().値(), 0.5);
    assert_eq!(当たり.交差位置(), 位置(1.25, 1.0, 0.5));
    assert_eq!(当たり.升目の添字().東添字(), 1);
    assert_eq!(当たり.升目の添字().南添字(), 0);
    assert_eq!(当たり.地表の面().三角形(), 升目の三角形::奥側);
    assert_eq!(当たり.地表の面().傾き().東の傾き(), 4.0);
    assert_eq!(当たり.地表の面().傾き().南の傾き(), 0.0);
}

/// 格子の広がりの外へ出る線分は、答えられない升目に達したところで走査を打ち切る。
/// 当たらなかったことではなく調べ切れなかったことを、結果の2つ目の軸が伝える。
#[test]
fn 広がりの外へ出る線分は打ち切りを伝える() {
    let 結果 = 当たりを求める(&平らな地形を作る(), 1.0, 位置(0.5, 1.0, 0.5), 位置(5.0, 1.0, 0.5));
    assert_eq!(結果.最初に当たる点(), 線分が地表に最初に当たる点::地表に当たらない);
    assert_eq!(結果.調べた範囲(), 線分の走査が調べた範囲::調べられない升目で打ち切った);
}

/// 始点が既に格子の広がりの外にある線分は、1つ目の升目で打ち切る。
#[test]
fn 始点が広がりの外にある線分は最初の升目で打ち切る() {
    let 結果 = 当たりを求める(&平らな地形を作る(), 1.0, 位置(-3.0, 1.0, 0.5), 位置(1.0, -1.0, 0.5));
    assert_eq!(結果.最初に当たる点(), 線分が地表に最初に当たる点::地表に当たらない);
    assert_eq!(結果.調べた範囲(), 線分の走査が調べた範囲::調べられない升目で打ち切った);
}
