//! 線分と高さ場の当たりの結果: 線分の問い合わせが返す2つの軸を1つにまとめた値である。
//! 1つ目の軸は最初に当たる点そのもの、2つ目の軸は走査が線分のどこまでを調べられたかである。
//!
//! 2軸に分ける理由は`線分の走査が調べた範囲`が持つ。世界の側はこの2軸目を問い合わせの完全性へ写す。

use super::scanned_range::線分の走査が調べた範囲;
use super::segment_hit::{地表への最初の当たり, 線分が地表に最初に当たる点};

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 線分と高さ場の当たりの結果 {
    最初に当たる点: 線分が地表に最初に当たる点,
    調べた範囲: 線分の走査が調べた範囲,
}

impl 線分と高さ場の当たりの結果 {
    /// 打ち切りに達する前に当たりを見つけた場合。手前の升目はすべて調べ切っているため、この当たりは
    /// 最初の当たりであると言い切れる。
    pub(super) fn 当たりを見つけた(当たり: 地表への最初の当たり) -> Self {
        Self {
            最初に当たる点: 線分が地表に最初に当たる点::地表に当たる(当たり),
            調べた範囲: 線分の走査が調べた範囲::線分の全体を調べた,
        }
    }

    pub(super) fn 当たらないまま線分の全体を調べた() -> Self {
        Self {
            最初に当たる点: 線分が地表に最初に当たる点::地表に当たらない,
            調べた範囲: 線分の走査が調べた範囲::線分の全体を調べた,
        }
    }

    pub(super) fn 当たらないまま調べられない升目で打ち切った() -> Self {
        Self {
            最初に当たる点: 線分が地表に最初に当たる点::地表に当たらない,
            調べた範囲: 線分の走査が調べた範囲::調べられない升目で打ち切った,
        }
    }

    pub fn 最初に当たる点(&self) -> 線分が地表に最初に当たる点 {
        self.最初に当たる点
    }

    pub fn 調べた範囲(&self) -> 線分の走査が調べた範囲 {
        self.調べた範囲
    }
}
