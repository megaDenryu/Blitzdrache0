//! 線分の水平投影が通る升目を、始点の側から順に1つずつ辿る走査。持つのは升目の並びと、その升目に居る間の
//! 媒介変数の区間だけであり、升目の中で地表に当たるかは持たない。
//!
//! この工程が要るのは、調べる升目を線分が実際に横断した升目だけに絞るためである。高さ場の升目を総当たりすると、
//! 計算量が世界の広さに比例してしまう。

use super::axis_traversal::軸ごとの升目の横断;
use super::cell_index::升目の格子添字;
use super::linear_in_parameter::媒介変数の1次式;

/// 線分が横断した升目1つと、その升目に居る間の媒介変数の区間。
/// 升目の中の比を1次式で持つのは、区間の中の任意の時刻で比を求め直せるようにするためである。
pub(super) struct 横断した升目 {
    添字: 升目の格子添字,
    東の比の1次式: 媒介変数の1次式,
    南の比の1次式: 媒介変数の1次式,
    入る時刻: f64,
    出る時刻: f64,
}

impl 横断した升目 {
    pub(super) fn 添字(&self) -> 升目の格子添字 {
        self.添字
    }

    pub(super) fn 東の比の1次式(&self) -> 媒介変数の1次式 {
        self.東の比の1次式
    }

    pub(super) fn 南の比の1次式(&self) -> 媒介変数の1次式 {
        self.南の比の1次式
    }

    pub(super) fn 入る時刻(&self) -> f64 {
        self.入る時刻
    }

    pub(super) fn 出る時刻(&self) -> f64 {
        self.出る時刻
    }
}

pub(super) enum 升目の横断の続き {
    次の升目(横断した升目),
    線分の終わりに達した,
    升目の添字を表せなくなった,
}

/// 走査が升目を返さなくなった理由。升目を返し終えた次の呼び出しで呼び出し側へ伝えるために保持する。
#[derive(Clone, Copy)]
enum 走査の終わり方 {
    まだ終わっていない,
    線分の終わりに達した,
    升目の添字を表せなくなった,
}

pub(super) struct 升目の横断の走査 {
    東の横断: 軸ごとの升目の横断,
    南の横断: 軸ごとの升目の横断,
    現在の時刻: f64,
    終わり方: 走査の終わり方,
}

impl 升目の横断の走査 {
    pub(super) fn 生成する(東の横断: 軸ごとの升目の横断, 南の横断: 軸ごとの升目の横断) -> Self {
        Self {
            東の横断,
            南の横断,
            現在の時刻: 0.0,
            終わり方: 走査の終わり方::まだ終わっていない,
        }
    }

    pub(super) fn 次の升目へ進む(&mut self) -> 升目の横断の続き {
        match self.終わり方 {
            走査の終わり方::線分の終わりに達した => return 升目の横断の続き::線分の終わりに達した,
            走査の終わり方::升目の添字を表せなくなった => {
                return 升目の横断の続き::升目の添字を表せなくなった;
            }
            走査の終わり方::まだ終わっていない => {}
        }
        let 東の境界 = self.東の横断.次に境界へ達する時刻();
        let 南の境界 = self.南の横断.次に境界へ達する時刻();
        let 早い境界 = if 東の境界 <= 南の境界 { 東の境界 } else { 南の境界 };
        let 升目 = 横断した升目 {
            添字: 升目の格子添字::生成する(self.東の横断.現在の升目の添字(), self.南の横断.現在の升目の添字()),
            東の比の1次式: self.東の横断.現在の升目の中の比の1次式(),
            南の比の1次式: self.南の横断.現在の升目の中の比の1次式(),
            入る時刻: self.現在の時刻,
            出る時刻: 早い境界.clamp(self.現在の時刻, 1.0),
        };
        self.現在の時刻 = 升目.出る時刻;
        self.終わり方 = self.隣の升目へ移った結果(東の境界, 南の境界, 早い境界);
        升目の横断の続き::次の升目(升目)
    }

    /// 返したばかりの升目の次へ移る。境界が線分の終わりより先にあるなら移らずに終わる。
    /// 2つの軸の境界が同じ時刻なら、線分は升目の角をちょうど通るため両方の軸で隣へ移る。
    fn 隣の升目へ移った結果(&mut self, 東の境界: f64, 南の境界: f64, 早い境界: f64) -> 走査の終わり方 {
        if 早い境界 >= 1.0 {
            return 走査の終わり方::線分の終わりに達した;
        }
        let 東へ移れた = 東の境界 > 南の境界 || self.東の横断.隣の升目へ移る().is_some();
        let 南へ移れた = 南の境界 > 東の境界 || self.南の横断.隣の升目へ移る().is_some();
        if 東へ移れた && 南へ移れた {
            走査の終わり方::まだ終わっていない
        } else {
            走査の終わり方::升目の添字を表せなくなった
        }
    }
}
