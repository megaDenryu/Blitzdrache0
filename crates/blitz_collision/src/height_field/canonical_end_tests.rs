//! 走査が持つ升目の縁の正準値が、交差の求解を通って当たりの答えまで保たれることの反証。
//! 見るのは2つであり、対角を越える端が区間の端と重なるときに元の端が返ること、当たりが区間の終わりの端に
//! 一致するときに地表の面と媒介変数が端の値のまま返ることである。
//!
//! 近くの境界で見ないのは、正準値を捨てても近くでは比の1次式の誤差が小さく、答えが同じ値になるためである。
//! 線分の始点から数えて数万升目の先では比の誤差が1の32ULPまで育ち、面の高さと媒介変数の最終桁に現れる。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断7: 高さ場の物理は最詳細段の三角形化と一致させる」

#![allow(clippy::unwrap_used)]

use super::cell_interval_end::{区間の端での軸の比, 升目に居る区間の端};
use super::linear_in_parameter::媒介変数の1次式;
use super::segment_query_fixture::{
    位置, 反例の境界に尾根がある地形を作る, 反例の境界の東添字, 反例の始点の東の実数添字, 反例の終点の東の実数添字, 当たりを取り出す, 当たりを求める,
};

/// 反例の線分が境界へ達する時刻。走査が求めるのとまったく同じ割り算であり、この値がそのまま当たりの時刻に
/// なることが、端の時刻を区間の幅の足し直しで求めていないことの反証になる。
fn 反例の境界へ達する時刻() -> f64 {
    let 実数添字の速度 = 反例の終点の東の実数添字 - 反例の始点の東の実数添字;
    (f64::from(反例の境界の東添字) - 反例の始点の東の実数添字) / 実数添字の速度
}

/// 反例の境界を出る升目の東の比の1次式。始値は始点の実数添字から升目の添字を引いた値である。
fn 反例の境界を出る升目の東の比の1次式() -> 媒介変数の1次式 {
    媒介変数の1次式::生成する(
        反例の始点の東の実数添字 - f64::from(反例の境界の東添字),
        反例の終点の東の実数添字 - 反例の始点の東の実数添字,
    )
}

/// 対角を越える時刻が区間の端と重なる退化した区間では、新しい端を作らずに元の端を返す。返した端が縁の上の
/// 厳密な零を答えることが、正準値を捨てていないことの反証である。1次式で求め直すと7.1×10^-15になる。
#[test]
fn 対角を越える時刻が区間の端と重なるときは端の正準値が保たれる() {
    let 出る端 = 升目に居る区間の端::生成する(
        反例の境界へ達する時刻(),
        区間の端での軸の比::添字の側の縁にあり零,
        区間の端での軸の比::升目の内側にあり1次式で求める,
    );
    let 入る端 = 升目に居る区間の端::升目の内側の時刻から生成する(0.0);
    let 出る端と重なる対角 = 升目に居る区間の端::区間の中で求めた時刻から生成する(出る端.時刻(), 入る端, 出る端);
    let 入る端と重なる対角 = 升目に居る区間の端::区間の中で求めた時刻から生成する(入る端.時刻(), 入る端, 出る端);
    assert_eq!(出る端と重なる対角, 出る端);
    assert_eq!(入る端と重なる対角, 入る端);
    assert_eq!(出る端と重なる対角.東の比を求める(反例の境界を出る升目の東の比の1次式()), 0.0);
}

/// 遠くの尾根のてっぺん(共有辺のちょうど上)へ水平に当たる線分。天頂は1メートルで一定であり、尾根の格子点の
/// 高さも1メートルであるから、地表に達するのは境界の上の1点だけである。当たりは升目を出る端そのものであり、
/// 面を1次式の比で求め直すと高さが1メートルから7.1×10^-15だけ下がり、時刻も区間の幅の足し直しで動く。
#[test]
fn 遠くの共有辺の上の当たりは面も媒介変数も端の値のまま返る() {
    let 結果 = 当たりを求める(
        &反例の境界に尾根がある地形を作る(),
        1.0,
        位置(反例の始点の東の実数添字, 1.0, 0.25),
        位置(反例の終点の東の実数添字, 1.0, 0.25),
    );
    let 当たり = 当たりを取り出す(結果);
    assert_eq!(当たり.交差時刻().値(), 反例の境界へ達する時刻());
    assert_eq!(当たり.升目の添字().東添字(), 反例の境界の東添字);
    assert_eq!(当たり.地表の面().高さ(), 1.0);
    assert_eq!(当たり.地表の面().傾き().東の傾き(), -1.0);
    assert_eq!(当たり.地表の面().傾き().南の傾き(), 0.0);
}
