//! 升目の隅: 升目を囲む4つの格子点のどれか1つである。手前が南の添字、奥が南の添字の次であり、
//! 左が東の添字、右が東の添字の次である。`升目の四隅の高さ`が並べる4つと同じ意味の語である。
//!
//! 名前で持つのは、掃引の接触が三角形の頂点で起きたときにどの格子点だったかを答えるためである。
//! 0から3の整数で答えると、並びの順番という別の約束を呼び出し側が覚えることになる。

/// 升目を囲む4つの格子点のどれか1つ。手前が南の添字、奥が南の添字の次であり、左が東の添字、右が東の添字の次である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[allow(missing_docs)] // 枝の説明は型の`///`が持つ。枝ごとの`///`は宣言の間のコメント行になり規約に反する
pub enum 升目の隅 {
    手前左,
    手前右,
    奥左,
    奥右,
}

impl 升目の隅 {
    /// 升目の左手前の格子点から東へいくつ進んだ格子点か。0か1である。
    pub fn 東へ進む格子点の数(self) -> u32 {
        match self {
            Self::手前右 | Self::奥右 => 1,
            Self::手前左 | Self::奥左 => 0,
        }
    }

    /// 升目の左手前の格子点から南へいくつ進んだ格子点か。0か1である。
    pub fn 南へ進む格子点の数(self) -> u32 {
        match self {
            Self::奥左 | Self::奥右 => 1,
            Self::手前左 | Self::手前右 => 0,
        }
    }
}
