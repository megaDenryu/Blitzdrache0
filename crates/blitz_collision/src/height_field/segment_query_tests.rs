//! 平らな地形に対する線分の交差の反証。斜めの線分・地表の上を通る線分・始点が地表の下にある線分・
//! 垂直に落ちる線分の4つを、手で解いた期待値と突き合わせる。
//!
//! 期待値はどれも1次方程式を手で解いて出す。線分の高さも地表の高さも媒介変数の1次式であるため、
//! 交差時刻は差の始値を差の減少量で割った商であり、割り切れる数を選べば厳密な値が書ける。

#![allow(clippy::unwrap_used)]

use super::segment_query_fixture::{位置, 平らな地形を作る, 当たりを取り出す, 当たりを求める};
use super::{升目の三角形, 線分が地表に最初に当たる点, 線分の走査が調べた範囲};

// 高さ1メートルから高さ-1メートルへ降りる線分は、高さの差が2メートル縮む間に1メートルぶん降りた時点で
// 地表(高さ0メートル)へ達するため、交差時刻は線分の中点である。東は0.25から0.75メートルへ進んで
// 升目(0, 0)に収まり、東の比0.5は南の比0.75より小さいので奥側の三角形である。
#[test]
fn 平らな地形を斜めに貫く線分は線分の中点で当たる() {
    let 結果 = 当たりを求める(&平らな地形を作る(), 1.0, 位置(0.25, 1.0, 0.75), 位置(0.75, -1.0, 0.75));
    assert_eq!(結果.調べた範囲(), 線分の走査が調べた範囲::線分の全体を調べた);
    let 当たり = 当たりを取り出す(結果);
    assert_eq!(当たり.交差時刻().値(), 0.5);
    assert_eq!(当たり.交差位置(), 位置(0.5, 0.0, 0.75));
    assert_eq!(当たり.升目の添字().東添字(), 0);
    assert_eq!(当たり.升目の添字().南添字(), 0);
    assert_eq!(当たり.地表の面().三角形(), 升目の三角形::奥側);
    assert_eq!(当たり.地表の面().高さ(), 0.0);
}

// 高さ1メートルから0.5メートルへ降りるだけの線分は地表へ届かない。調べた範囲が線分の全体であることも見る。
// 当たらなかったことと調べ切れなかったことは別の事実だからである。
#[test]
fn 地表の上を通る線分は当たらない() {
    let 結果 = 当たりを求める(&平らな地形を作る(), 1.0, 位置(0.25, 1.0, 0.75), 位置(1.75, 0.5, 0.75));
    assert_eq!(結果.最初に当たる点(), 線分が地表に最初に当たる点::地表に当たらない);
    assert_eq!(結果.調べた範囲(), 線分の走査が調べた範囲::線分の全体を調べた);
}

// 始点が既に地表より下にある線分は、始点そのもので当たったものとして交差時刻0を返す。
// 遮蔽の問い合わせで「始めから地面の中に居る」を「遮られていない」と答えてはならないためである。
#[test]
fn 始点が地表の下にある線分は交差時刻0で当たる() {
    let 結果 = 当たりを求める(&平らな地形を作る(), 1.0, 位置(0.25, -1.0, 0.75), 位置(0.75, 2.0, 0.75));
    let 当たり = 当たりを取り出す(結果);
    assert_eq!(当たり.交差時刻().値(), 0.0);
    assert_eq!(当たり.交差位置(), 位置(0.25, -1.0, 0.75));
}

// 水平投影が1点になる線分でも走査は升目を1つ返す。高さ3メートルから-1メートルへ落ちる線分は、
// 高さの差が4メートル縮む間に3メートルぶん降りた時点で地表へ達するため、交差時刻は0.75である。
#[test]
fn 垂直に落ちる線分も正しく当たる() {
    let 結果 = 当たりを求める(&平らな地形を作る(), 1.0, 位置(0.25, 3.0, 0.75), 位置(0.25, -1.0, 0.75));
    let 当たり = 当たりを取り出す(結果);
    assert_eq!(当たり.交差時刻().値(), 0.75);
    assert_eq!(当たり.交差位置(), 位置(0.25, 0.0, 0.75));
    assert_eq!(当たり.升目の添字().東添字(), 0);
    assert_eq!(当たり.升目の添字().南添字(), 0);
}

// 同じ入力を2回評価した結果が浮動小数点のビット列まで一致することを見る。決定性(判断14)の反証である。
#[test]
fn 同じ入力は2回評価してもビット単位で同じ結果になる() {
    let 地形 = 平らな地形を作る();
    let 最初の当たり = 当たりを取り出す(当たりを求める(&地形, 1.0, 位置(0.3, 1.7, 0.9), 位置(1.9, -1.3, 0.4)));
    let もう一度の当たり = 当たりを取り出す(当たりを求める(&地形, 1.0, 位置(0.3, 1.7, 0.9), 位置(1.9, -1.3, 0.4)));
    assert_eq!(最初の当たり.交差時刻().値().to_bits(), もう一度の当たり.交差時刻().値().to_bits());
    let 最初の位置 = 最初の当たり.交差位置();
    let もう一度の位置 = もう一度の当たり.交差位置();
    assert_eq!(最初の位置.東のメートル().to_bits(), もう一度の位置.東のメートル().to_bits());
    assert_eq!(最初の位置.天頂のメートル().to_bits(), もう一度の位置.天頂のメートル().to_bits());
    assert_eq!(最初の位置.南のメートル().to_bits(), もう一度の位置.南のメートル().to_bits());
    assert_eq!(最初の当たり.地表の面().高さ().to_bits(), もう一度の当たり.地表の面().高さ().to_bits());
}
