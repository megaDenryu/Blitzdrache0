//! 線分の走査が調べた範囲: 升目の横断が線分のどこまでを実際に調べられたかを表す。
//!
//! 当たったかどうかとは別の軸に置くのは、「当たらなかった」と「調べられなかったので分からない」が
//! 別の事実だからである。供給元が答えを持たない升目に達した走査はそこで打ち切る。打ち切った先に
//! もっと手前の当たりがありえないとは言えず、その先で見つけた当たりは「最初の当たり」を名乗れないためである。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 線分の走査が調べた範囲 {
    線分の全体を調べた,           // 始点から終点まで、通ったすべての升目を調べ切った
    調べられない升目で打ち切った, // 四隅の高さを答えられない升目に達し、その手前までで止めた
}
