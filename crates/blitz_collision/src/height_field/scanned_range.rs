//! 線分の走査が調べた範囲: 最初の当たりの答えが確定的かどうかを表す。
//!
//! 当たったかどうかとは別の軸に置くのは、「当たらなかった」と「調べられなかったので分からない」が
//! 別の事実だからである。供給元が答えを持たない升目に達した走査はそこで打ち切る。打ち切った先に
//! もっと手前の当たりがありえないとは言えず、その先で見つけた当たりは「最初の当たり」を名乗れないためである。
//!
//! 打ち切りが立つのは当たらなかった側だけである。答えられない升目で走査を止める設計により、当たりを
//! 見つけた時点では手前の升目をすべて調べ終えているからである。したがって「確定した当たり」と
//! 「その手前の未評価」が同時に立つ答えは作れない。

/// 線分の走査が線分の全体を調べ切れたか。最初の当たりの答えが確定的かどうかの軸である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[allow(missing_docs)] // 枝の説明は型の`///`が持つ。枝ごとの`///`は宣言の間のコメント行になり規約に反する
pub enum 線分の走査が調べた範囲 {
    線分の全体を調べた,           // 始点から当たり(当たらなければ終点)まで、通ったすべての升目を調べ切った
    調べられない升目で打ち切った, // 四隅の高さを答えられない升目に達し、その手前までで止めた
}
