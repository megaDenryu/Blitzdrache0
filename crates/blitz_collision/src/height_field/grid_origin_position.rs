//! 高さ場の格子原点からの位置: 高さ場の格子原点を基準にした位置である。成分の並びは東・天頂・南であり、
//! 単位はメートル、精度は倍精度である。天頂の基準は高さの標本と同じであり、格子原点によってずれない。
//!
//! 大域の位置と別の型にするのは、衝突数学層が世界の原点も世界の広がりも知らず、格子の原点だけを基準に
//! できるためである。大域の位置からこの位置へ写すのは、格子原点を知っている世界の側の仕事である。
//! 倍精度に固定するのは、この位置が実行中の問い合わせにだけ現れ、焼き込みの単精度の経路には現れないためである。

use super::segment_error::線分の問い合わせエラー;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 高さ場の格子原点からの位置 {
    東のメートル: f64,
    天頂のメートル: f64,
    南のメートル: f64,
}

impl 高さ場の格子原点からの位置 {
    pub fn 生成する(
        東のメートル: f64, 天頂のメートル: f64, 南のメートル: f64
    ) -> Result<Self, 線分の問い合わせエラー> {
        if [東のメートル, 天頂のメートル, 南のメートル].into_iter().any(|値| !値.is_finite()) {
            return Err(線分の問い合わせエラー::線分の端点が有限でない);
        }
        Ok(Self {
            東のメートル,
            天頂のメートル,
            南のメートル,
        })
    }

    pub fn 東のメートル(&self) -> f64 {
        self.東のメートル
    }

    pub fn 天頂のメートル(&self) -> f64 {
        self.天頂のメートル
    }

    pub fn 南のメートル(&self) -> f64 {
        self.南のメートル
    }
}
