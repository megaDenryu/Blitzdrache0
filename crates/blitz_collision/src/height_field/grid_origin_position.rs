//! 高さ場の格子原点からの位置: 高さ場の格子原点を基準にした位置である。成分の並びは東・天頂・南であり、
//! 単位はメートル、精度は倍精度である。天頂の基準は高さの標本と同じであり、格子原点によってずれない。
//!
//! 大域の位置と別の型にするのは、衝突数学層が世界の原点も世界の広がりも知らず、格子の原点だけを基準に
//! できるためである。大域の位置からこの位置へ写すのは、格子原点を知っている世界の側の仕事である。
//! 倍精度に固定するのは、この位置が実行中の問い合わせにだけ現れ、焼き込みの単精度の経路には現れないためである。

use super::grid_origin_displacement::高さ場の中の変位;
use super::position_error::高さ場の位置の生成エラー;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 高さ場の格子原点からの位置 {
    東のメートル: f64,
    天頂のメートル: f64,
    南のメートル: f64,
}

impl 高さ場の格子原点からの位置 {
    pub fn 生成する(
        東のメートル: f64, 天頂のメートル: f64, 南のメートル: f64
    ) -> Result<Self, 高さ場の位置の生成エラー> {
        if [東のメートル, 天頂のメートル, 南のメートル].into_iter().any(|値| !値.is_finite()) {
            return Err(高さ場の位置の生成エラー::位置の成分が有限でない);
        }
        Ok(Self {
            東のメートル,
            天頂のメートル,
            南のメートル,
        })
    }

    pub fn 東のメートル(&self) -> f64 {
        self.東のメートル
    }

    pub fn 天頂のメートル(&self) -> f64 {
        self.天頂のメートル
    }

    pub fn 南のメートル(&self) -> f64 {
        self.南のメートル
    }

    /// この位置から終点へ向かう変位。
    pub fn 終点までの変位を求める(&self, 終点: Self) -> 高さ場の中の変位 {
        高さ場の中の変位::演算の結果から組む(
            終点.東のメートル - self.東のメートル,
            終点.天頂のメートル - self.天頂のメートル,
            終点.南のメートル - self.南のメートル,
        )
    }

    /// 変位だけ進んだ位置。成分が有限でなくなる入力を型付きエラーで拒む。
    pub fn 変位だけ進んだ位置を求める(&self, 変位: 高さ場の中の変位) -> Result<Self, 高さ場の位置の生成エラー> {
        Self::生成する(
            self.東のメートル + 変位.東のメートル(),
            self.天頂のメートル + 変位.天頂のメートル(),
            self.南のメートル + 変位.南のメートル(),
        )
    }
}
