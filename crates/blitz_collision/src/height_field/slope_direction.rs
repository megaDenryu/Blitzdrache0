//! 地表の傾きから、上向きの単位法線と2方向の単位接線を導く工程。触れるのは東の傾きと南の傾きの2つだけである。
//!
//! 傾きの保持と別のファイルへ置くのは、長さを1に正す計算と単位向きの型を知るのがこの工程だけであり、
//! 傾き自身は自分の2つの数と大きさの二乗しか知らないためである。

use super::real::地表の平面の実数;
use super::slope::地表の傾き;
use super::unit_direction::地表の単位向き;

impl<数: 地表の平面の実数> 地表の傾き<数> {
    /// 上向きの単位法線。高さの勾配が(東の傾き, 南の傾き)である平面の法線は、正す前が(-東の傾き, 1, -南の傾き)である。
    /// 天頂成分が正であるため、この向きが真下を向くことはない。
    pub fn 上向きの単位法線(&self) -> 地表の単位向き<数> {
        地表の単位向き::正して生成する(-self.東の傾き(), 数::一(), -self.南の傾き())
    }

    /// 東へ1メートル進む向きの単位接線。正す前は(1, 東の傾き, 0)である。
    pub fn 東向きの単位接線(&self) -> 地表の単位向き<数> {
        地表の単位向き::正して生成する(数::一(), self.東の傾き(), 数::零())
    }

    /// 南へ1メートル進む向きの単位接線。正す前は(0, 南の傾き, 1)である。
    pub fn 南向きの単位接線(&self) -> 地表の単位向き<数> {
        地表の単位向き::正して生成する(数::零(), self.南の傾き(), 数::一())
    }
}
