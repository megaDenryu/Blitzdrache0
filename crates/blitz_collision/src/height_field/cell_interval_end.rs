//! 升目に居る区間の端: 線分が1つの升目に居る区間の、片方の端である。その時刻と、その時刻に升目の境界を
//! 横断した軸の比を持つ。
//!
//! 境界を横断した軸の比を1次式の評価で求め直さないのは、大きな2つの量の相殺で誤差が育つためである。
//! 比の1次式は「始点の実数添字から升目の添字を引いた値」に「実数添字の速度と時刻の積」を足す形であり、
//! どちらの項も始点からその境界までに横断した升目の数まで大きくなる。結果は0以上1以下であるから、
//! 相殺した桁だけ誤差が残り、比の絶対誤差は横断する升目の数に比例して育つ。境界のちょうど上の比は
//! 走査が厳密に知っている(添字が増える向きへ進む軸は添字の側の縁から入って次の添字の側の縁から出る。
//! 減る向きへ進む軸では逆である)ため、求め直さずにその正準値を渡す。
//! 区間の内側の時刻(対角を越える時刻・当たりの時刻)は正準値を持たないため1次式で求める。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断7: 高さ場の物理は最詳細段の三角形化と一致させる」

use super::linear_in_parameter::媒介変数の1次式;

/// 区間の端での1つの軸の比。境界を横断した軸だけが升目の縁のちょうど上に居て、厳密な0か1を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) enum 区間の端での軸の比 {
    添字の側の縁にあり零,
    次の添字の側の縁にあり一,
    升目の内側にあり1次式で求める,
}

impl 区間の端での軸の比 {
    /// 升目から出る側の縁の比。実数添字が増える向きへ進む軸は次の添字の側の縁から出るため一であり、
    /// 減る向きへ進む軸は添字の側の縁から出るため零である。進まない軸は縁を横断しない。
    pub(super) fn 升目から出る側の縁として生成する(実数添字の速度: f64) -> Self {
        if 実数添字の速度 > 0.0 {
            Self::次の添字の側の縁にあり一
        } else if 実数添字の速度 < 0.0 {
            Self::添字の側の縁にあり零
        } else {
            Self::升目の内側にあり1次式で求める
        }
    }

    /// 同じ境界を隣の升目から見た比。一方の升目が出る縁は、隣の升目では入る縁である。
    fn 隣の升目から見た比にする(self) -> Self {
        match self {
            Self::添字の側の縁にあり零 => Self::次の添字の側の縁にあり一,
            Self::次の添字の側の縁にあり一 => Self::添字の側の縁にあり零,
            Self::升目の内側にあり1次式で求める => Self::升目の内側にあり1次式で求める,
        }
    }

    fn 値を求める(self, 比の1次式: 媒介変数の1次式, 時刻: f64) -> f64 {
        match self {
            Self::添字の側の縁にあり零 => 0.0,
            Self::次の添字の側の縁にあり一 => 1.0,
            Self::升目の内側にあり1次式で求める => 比の1次式.値を求める(時刻),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 升目に居る区間の端 {
    時刻: f64,
    東の比: 区間の端での軸の比,
    南の比: 区間の端での軸の比,
}

impl 升目に居る区間の端 {
    pub(super) fn 生成する(時刻: f64, 東の比: 区間の端での軸の比, 南の比: 区間の端での軸の比) -> Self {
        Self {
            時刻, 東の比, 南の比
        }
    }

    /// 升目の境界を横断していない時刻の端。走査の始まりの時刻、線分の終わりの時刻、対角を越える時刻がこれである。
    pub(super) fn 升目の内側の時刻から生成する(時刻: f64) -> Self {
        let 内側 = 区間の端での軸の比::升目の内側にあり1次式で求める;
        Self::生成する(時刻, 内側, 内側)
    }

    /// 同じ時刻を隣の升目から見た端。一方の升目を出る端は、隣の升目に入る端である。
    pub(super) fn 隣の升目から見た端にする(&self) -> Self {
        Self::生成する(self.時刻, self.東の比.隣の升目から見た比にする(), self.南の比.隣の升目から見た比にする())
    }

    pub(super) fn 時刻(&self) -> f64 {
        self.時刻
    }

    pub(super) fn 東の比を求める(&self, 東の比の1次式: 媒介変数の1次式) -> f64 {
        self.東の比.値を求める(東の比の1次式, self.時刻)
    }

    pub(super) fn 南の比を求める(&self, 南の比の1次式: 媒介変数の1次式) -> f64 {
        self.南の比.値を求める(南の比の1次式, self.時刻)
    }
}
