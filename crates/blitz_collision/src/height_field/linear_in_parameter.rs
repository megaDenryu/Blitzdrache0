//! 媒介変数の1次式: 線分の媒介変数について1次で変わる量を、始値と全体の変化量で表したものである。
//!
//! 走査と交差の求解が扱う量(升目の中の東と南の比、線分の天頂のメートル)は、どれも媒介変数の1次式である。
//! 始値と変化量を裸の2つの実数で持ち回すと、どちらがどの量の始値かを署名が語らなくなるためこの型で包む。

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 媒介変数の1次式 {
    始値: f64,
    全体の変化量: f64,
}

impl 媒介変数の1次式 {
    pub(super) fn 生成する(始値: f64, 全体の変化量: f64) -> Self {
        Self { 始値, 全体の変化量 }
    }

    /// 始点の値と終点の値から作る。線分の両端で決まる量はこの入口を通す。
    pub(super) fn 両端の値から生成する(始点の値: f64, 終点の値: f64) -> Self {
        Self::生成する(始点の値, 終点の値 - 始点の値)
    }

    pub(super) fn 値を求める(&self, 媒介変数: f64) -> f64 {
        self.始値 + self.全体の変化量 * 媒介変数
    }
}
