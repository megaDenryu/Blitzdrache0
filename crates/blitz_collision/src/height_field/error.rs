//! 升目を表す値の生成で破れる条件。持つのは値そのものの破れだけであり、問い合わせ位置が高さ場の広がりの
//! 外だったことは持たない。それは世界の側の失敗であり、この層は世界を知らないためである。

use thiserror::Error;

/// 升目を表す値の生成で破れる条件。四隅の高さ・升目の中の比・升目の一辺・升目の地表の面のそれぞれが守る条件である。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
#[allow(missing_docs)] // 枝の説明は型の`///`が持つ。枝ごとの`///`は宣言の間のコメント行になり規約に反する
pub enum 升目の値の生成エラー {
    #[error("升目の四隅の高さに有限でない値が含まれる")]
    四隅の高さが有限でない,
    #[error("升目の四隅の高さの絶対値が上限を越えている")]
    四隅の高さの絶対値が上限を越えている,
    #[error("升目の中の比が0以上1以下の有限値でない")]
    升目の中の比が範囲外,
    #[error("升目の一辺が正の有限値でない")]
    升目の一辺が正の有限値でない,
    #[error("升目の地表の面の高さか傾きが有限でない")]
    地表の面の高さか傾きが有限でない,
}
