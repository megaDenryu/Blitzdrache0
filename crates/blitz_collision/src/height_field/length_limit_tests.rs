//! 長さの絶対値の上限の反証。上限を越える位置・変位・半径が型付きエラーで拒まれること、上限ちょうどが
//! 受け付けられること、求解が導いた点には上限が掛からないことを見る。
//!
//! 指摘された反例(中心の高さ10の155乗メートル・半径1メートル・天頂の変位マイナス10の155乗メートル)は、
//! 上限を課す前は判別式が有限でなくなって「覆いをすべて調べて触れなかった」を返していた。上限を課した後は
//! 掃引を組む手前で拒まれるため、この反証は掃引の答えでなく生成の破れとして書く。

#![allow(clippy::unwrap_used)]

use super::{
    カプセルの掃引の問い合わせエラー, 高さ場の中の変位, 高さ場の位置の生成エラー, 高さ場の問い合わせが受け付ける長さの絶対値の上限メートル,
    高さ場の格子原点からの位置, 高さ場を掃引するカプセル,
};

#[test]
fn 上限を越える高さの位置は型付きエラーで拒む() {
    assert_eq!(
        高さ場の格子原点からの位置::生成する(0.0, 1.0e155, 0.0),
        Err(高さ場の位置の生成エラー::位置の成分の絶対値が上限を越えている)
    );
}

#[test]
fn 上限を越える天頂の変位は型付きエラーで拒む() {
    assert_eq!(
        高さ場の中の変位::生成する(0.0, -1.0e155, 0.0),
        Err(高さ場の位置の生成エラー::変位の成分の絶対値が上限を越えている)
    );
}

#[test]
fn 上限を越える半径のカプセルは型付きエラーで拒む() {
    let 始点 = 高さ場の格子原点からの位置::生成する(0.0, 0.0, 0.0).unwrap();
    let 終点 = 高さ場の格子原点からの位置::生成する(0.0, 1.0, 0.0).unwrap();
    let 変位 = 高さ場の中の変位::生成する(0.0, -1.0, 0.0).unwrap();
    let 上限を越える半径 = 高さ場の問い合わせが受け付ける長さの絶対値の上限メートル * 2.0;
    assert_eq!(
        高さ場を掃引するカプセル::生成する(始点, 終点, 上限を越える半径, 変位),
        Err(カプセルの掃引の問い合わせエラー::カプセルの半径が上限を越えている)
    );
}

/// 上限ちょうどは受け付ける。四隅の高さの上限と同じ値であるから、上限ちょうどの高さを持つ格子点は
/// 自分の位置を作れなければならない。
#[test]
fn 上限ちょうどの位置と変位と半径は受け付ける() {
    let 上限 = 高さ場の問い合わせが受け付ける長さの絶対値の上限メートル;
    let 始点 = 高さ場の格子原点からの位置::生成する(上限, -上限, 上限).unwrap();
    let 終点 = 高さ場の格子原点からの位置::生成する(上限, -上限, 上限).unwrap();
    let 変位 = 高さ場の中の変位::生成する(-上限, 上限, -上限).unwrap();
    assert!(高さ場を掃引するカプセル::生成する(始点, 終点, 上限, 変位).is_ok());
}

/// 求解が導いた点は上限の外へ出うる。三角形の平面へ落とした足は、平面が立っているほど遠くへ出るためである。
/// 上限を導いた点にも課すと、その候補が三角形の外だと分かる手前で問い合わせ全体が止まる。
#[test]
fn 変位だけ進んだ位置は上限を越えても作れる() {
    let 上限 = 高さ場の問い合わせが受け付ける長さの絶対値の上限メートル;
    let 位置 = 高さ場の格子原点からの位置::生成する(上限, 0.0, 0.0).unwrap();
    let 進んだ位置 = 位置
        .変位だけ進んだ位置を求める(高さ場の中の変位::生成する(上限, 0.0, 0.0).unwrap())
        .unwrap();
    assert_eq!(進んだ位置.東のメートル(), 上限 * 2.0);
}
