//! 高さ場を貫く線分: 高さ場の地表に当たるかを問い合わせる、始点と終点で決まる線分である。
//! 半直線でも直線でもなく線分であるのは、利用者(視点と注視点の間の遮蔽、次の刻みまでの移動)が
//! どちらの端も持っているためである。
//!
//! 端点が有限であることは`高さ場の格子原点からの位置`の生成が保証するため、この型は検査を持たない。

use super::grid_origin_position::高さ場の格子原点からの位置;
use super::linear_in_parameter::媒介変数の1次式;
use super::segment_error::線分の問い合わせエラー;
use super::segment_parameter::線分の媒介変数;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 高さ場を貫く線分 {
    始点: 高さ場の格子原点からの位置,
    終点: 高さ場の格子原点からの位置,
}

impl 高さ場を貫く線分 {
    pub fn 生成する(始点: 高さ場の格子原点からの位置, 終点: 高さ場の格子原点からの位置) -> Self {
        Self { 始点, 終点 }
    }

    pub fn 始点(&self) -> 高さ場の格子原点からの位置 {
        self.始点
    }

    pub fn 終点(&self) -> 高さ場の格子原点からの位置 {
        self.終点
    }

    /// 媒介変数で指し示す線分上の点。成分ごとの1次式で求めるため、始点と終点をそのまま返す端でも誤差が入らない。
    /// 端点が有限でも成分の差が浮動小数点の表せる範囲を越えうるため、生成の検査を通し直す。
    pub fn 線分上の点を求める(
        &self,
        媒介変数: 線分の媒介変数,
    ) -> Result<高さ場の格子原点からの位置, 線分の問い合わせエラー> {
        let 時刻 = 媒介変数.値();
        高さ場の格子原点からの位置::生成する(
            self.東のメートルの1次式().値を求める(時刻),
            self.天頂のメートルの1次式().値を求める(時刻),
            self.南のメートルの1次式().値を求める(時刻),
        )
    }

    pub(super) fn 東のメートルの1次式(&self) -> 媒介変数の1次式 {
        媒介変数の1次式::両端の値から生成する(self.始点.東のメートル(), self.終点.東のメートル())
    }

    pub(super) fn 天頂のメートルの1次式(&self) -> 媒介変数の1次式 {
        媒介変数の1次式::両端の値から生成する(self.始点.天頂のメートル(), self.終点.天頂のメートル())
    }

    pub(super) fn 南のメートルの1次式(&self) -> 媒介変数の1次式 {
        媒介変数の1次式::両端の値から生成する(self.始点.南のメートル(), self.終点.南のメートル())
    }
}
