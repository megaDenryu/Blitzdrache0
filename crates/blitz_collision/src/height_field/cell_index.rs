//! 升目の格子添字: 高さ場の格子の中で升目を1つ指す、東と南の整数の対である。升目の左手前の格子点の添字が
//! その升目を指すという規約は、升目の四隅の高さの並びと同じものである。
//!
//! 符号付きの整数で持つのは、走査の始点が格子の広がりの外にありうるためである。格子の外を指す添字は
//! 供給元が答えを持たない升目として扱われ、走査はそこで打ち切られる。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 升目の格子添字 {
    東添字: i32,
    南添字: i32,
}

impl 升目の格子添字 {
    pub fn 生成する(東添字: i32, 南添字: i32) -> Self {
        Self { 東添字, 南添字 }
    }

    /// 升目の左手前の格子点の東添字。升目はこの添字と次の添字の間を占める。
    pub fn 東添字(&self) -> i32 {
        self.東添字
    }

    /// 升目の左手前の格子点の南添字。升目はこの添字と次の添字の間を占める。
    pub fn 南添字(&self) -> i32 {
        self.南添字
    }
}
