//! 地表の単位向き: 地表の面に結び付く長さ1の向きである。成分の並びは東・天頂・南であり、無次元量である。
//!
//! `blitz_math`の`方向`と別の型にするのは、`方向`が単精度であり、倍精度で導いた向きを単精度へ狭める場所を
//! `方向へ狭める`の1箇所へ閉じるためである。単精度で計算した呼び出し側は、狭めずに成分をそのまま読める。

use blitz_math::{方向, 方向エラー, 空間};

use super::real::地表の平面の実数;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 地表の単位向き<数> {
    東成分: 数,
    天頂成分: 数,
    南成分: 数,
}

impl<数: 地表の平面の実数> 地表の単位向き<数> {
    /// 長さを1に正して作る。長さが0または非有限になる入力は成分が非有限になり、`方向へ狭める`が型付きエラーで拒む。
    pub(super) fn 正して生成する(東成分: 数, 天頂成分: 数, 南成分: 数) -> Self {
        let 長さ = (東成分 * 東成分 + 天頂成分 * 天頂成分 + 南成分 * 南成分).平方根();
        Self {
            東成分: 東成分 / 長さ,
            天頂成分: 天頂成分 / 長さ,
            南成分: 南成分 / 長さ,
        }
    }

    pub fn 東成分(&self) -> 数 {
        self.東成分
    }

    pub fn 天頂成分(&self) -> 数 {
        self.天頂成分
    }

    pub fn 南成分(&self) -> 数 {
        self.南成分
    }

    /// `blitz_math`の単位方向へ写す。東成分・天頂成分・南成分がそのままx・y・zになる。
    pub fn 方向へ狭める<空間種: 空間>(&self) -> Result<方向<空間種>, 方向エラー> {
        数::成分を方向へ狭める(self.東成分, self.天頂成分, self.南成分)
    }
}
