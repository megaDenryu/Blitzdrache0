//! 升目の中の比: 升目の左手前の格子点から見て、東と南へそれぞれ升目の一辺の何倍だけ進んだ位置かを表す
//! 0以上1以下の無次元量である。2つの実数を裸で運ばないのは、東と南を取り違えても実数のままでは型が通るためである。
//!
//! 点がどちらの三角形に属するかは升目の中の比だけで決まるため、三角形を選ぶ操作もこの型が持つ。

use super::error::升目の値の生成エラー;
use super::real::地表の平面の実数;
use super::triangle::升目の三角形;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 升目の中の比<数> {
    東の比: 数,
    南の比: 数,
}

impl<数: 地表の平面の実数> 升目の中の比<数> {
    pub fn 生成する(東の比: 数, 南の比: 数) -> Result<Self, 升目の値の生成エラー> {
        for 値 in [東の比, 南の比] {
            if !値.有限か() || 値 < 数::零() || 値 > 数::一() {
                return Err(升目の値の生成エラー::升目の中の比が範囲外);
            }
        }
        Ok(Self { 東の比, 南の比 })
    }

    /// 0以上1以下からわずかに外れた比を、升目の縁へ寄せて作る。升目の境界の上の比は走査が正準値で渡すため
    /// ここへは来ないが、区間の内側の時刻の比は1次式で求めており、大きな2項の相殺で0や1をほんの少し越えることがある。
    /// 寄せる量はその誤差、すなわち線分の始点から数えた升目の数に比例する量であり、面の高さがそのぶん動く量は
    /// 四隅の高さの絶対値の上限に比例して抑えられる。非有限の値は寄せずに型付きエラーで拒む。
    /// 参照: `_doc/設計/世界の形と衝突基盤.md`「判断7」の「区間の内側の比は、始点からの距離に比例して誤差が育つ」
    pub(super) fn 縁へ寄せて生成する(東の比: 数, 南の比: 数) -> Result<Self, 升目の値の生成エラー> {
        Self::生成する(比を0以上1以下へ寄せる(東の比)?, 比を0以上1以下へ寄せる(南の比)?)
    }

    pub fn 東の比(&self) -> 数 {
        self.東の比
    }

    pub fn 南の比(&self) -> 数 {
        self.南の比
    }

    /// 点が属する三角形。対角の上(東の比と南の比が等しい)では奥側を選ぶ。対角の上では2つの三角形の平面が
    /// 同じ高さを返すため、判定の等号をどちらへ寄せても面は途切れない。
    pub fn 属する三角形を求める(&self) -> 升目の三角形 {
        if self.東の比 <= self.南の比 {
            升目の三角形::奥側
        } else {
            升目の三角形::手前側
        }
    }
}

fn 比を0以上1以下へ寄せる<数: 地表の平面の実数>(値: 数) -> Result<数, 升目の値の生成エラー> {
    if !値.有限か() {
        return Err(升目の値の生成エラー::升目の中の比が範囲外);
    }
    if 値 < 数::零() {
        return Ok(数::零());
    }
    if 値 > 数::一() {
        return Ok(数::一());
    }
    Ok(値)
}
