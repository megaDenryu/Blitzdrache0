//! 地表の傾き: 東と南それぞれについて、1メートル進むときに何メートル上がるかを表す無次元量である。
//! 角度でなくこの形で持つのは、逆三角関数を通さずに法線と接線を組めるためである。
//!
//! 生成に有限性の検査を置かず、面へ組む`升目の地表の面::生成する`が高さと2方向の傾きをまとめて検査する。
//! 四隅の高さと升目の一辺が検査済みでも、四隅の高さの差は浮動小数点の表せる範囲を越えうるため、
//! 検査そのものを省いてよいという意味ではない。この型を単体で作って向きへ写した場合は、
//! 境界(`地表の単位向き`の`方向へ狭める`)が非有限の成分と単位長でない長さを型付きエラーで拒む。

use super::real::地表の平面の実数;

/// 東と南それぞれについて、1メートル進むときに何メートル上がるかを表す無次元量。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 地表の傾き<数> {
    東の傾き: 数,
    南の傾き: 数,
}

impl<数: 地表の平面の実数> 地表の傾き<数> {
    /// 東の傾きと南の傾きから作る。有限性は面へ組む`升目の地表の面::生成する`が確かめる。
    pub fn 生成する(東の傾き: 数, 南の傾き: 数) -> Self {
        Self { 東の傾き, 南の傾き }
    }

    /// 東へ1メートル進むときに上がるメートル。
    pub fn 東の傾き(&self) -> 数 {
        self.東の傾き
    }

    /// 南へ1メートル進むときに上がるメートル。
    pub fn 南の傾き(&self) -> 数 {
        self.南の傾き
    }

    /// 傾きの大きさの二乗。平方根を通さないのは、面の緩急の判定が閾値の二乗と比べるだけで済むためである。
    pub fn 大きさの二乗(&self) -> 数 {
        self.東の傾き * self.東の傾き + self.南の傾き * self.南の傾き
    }
}
