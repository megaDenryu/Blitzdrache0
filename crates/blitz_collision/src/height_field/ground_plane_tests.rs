//! 区分線形の面の反証。三角形の選択が対角の両側で切り替わること、対角の上で2つの三角形の平面が同じ高さを
//! 返すこと、四隅が同一平面に乗らない鞍型の升目で双一次と違う三角形の面の値になること、傾きが選んだ三角形の
//! 辺の高さの差から出ることを見る。値オブジェクトが壊れた入力と上限を越えた高さを拒むことと、四隅が
//! 受け付ける範囲にあっても傾きが桁あふれする升目を面の生成が拒むこともここで確かめる。

#![allow(clippy::unwrap_used)]

use super::{
    升目の一辺, 升目の三角形, 升目の中の比, 升目の値の生成エラー, 升目の四隅の高さ, 升目の地表の面, 地表の高さの絶対値の上限メートル
};

/// 四隅が同一平面に乗らない鞍型の升目。手前左0・手前右1・奥左1・奥右0であり、升目の一辺は2メートルである。
fn 鞍型の面(東の比: f64, 南の比: f64) -> 升目の地表の面<f64> {
    let 四隅 = 升目の四隅の高さ::生成する(0.0, 1.0, 1.0, 0.0).unwrap();
    四隅
        .地表の面を求める(升目の中の比::生成する(東の比, 南の比).unwrap(), 升目の一辺::生成する(2.0).unwrap())
        .unwrap()
}

/// 鞍型の升目の四隅を双一次で混ぜた高さ。区分線形と値が見分けられることを示すためだけに置く。
fn 鞍型の双一次の高さ(東の比: f64, 南の比: f64) -> f64 {
    let 手前 = 0.0 + (1.0 - 0.0) * 東の比;
    let 奥 = 1.0 + (0.0 - 1.0) * 東の比;
    手前 + (奥 - 手前) * 南の比
}

#[test]
fn 対角の両側で属する三角形が切り替わる() {
    assert_eq!(鞍型の面(0.25, 0.75).三角形(), 升目の三角形::奥側);
    assert_eq!(鞍型の面(0.75, 0.25).三角形(), 升目の三角形::手前側);
    assert_eq!(鞍型の面(0.5, 0.5).三角形(), 升目の三角形::奥側);
}

/// 鞍型の升目では、対角の上の高さは奥側の式でも手前側の式でも0になる(手前左0に、差1と差-1が同じ比で加わる)。
/// 対角のすぐ手前側で高さが0のままであることが、2つの式が対角で一致していることの反証になる。
#[test]
fn 対角の上では2つの三角形の平面が同じ高さを返す() {
    for 比 in [0.0, 0.25, 0.5, 0.75, 1.0] {
        assert_eq!(鞍型の面(比, 比).高さ(), 0.0, "対角の比{比}で高さが0でない");
    }
    let すぐ手前側 = 鞍型の面(0.5 + 1.0e-9, 0.5);
    assert_eq!(すぐ手前側.三角形(), 升目の三角形::手前側);
    assert!(
        すぐ手前側.高さ().abs() < 1.0e-8,
        "対角のすぐ手前側で面が途切れている: {}",
        すぐ手前側.高さ()
    );
}

#[test]
fn 鞍型の升目では双一次と違う三角形の面の値を返す() {
    assert_eq!(鞍型の面(0.25, 0.75).高さ(), 0.5);
    assert_eq!(鞍型の面(0.75, 0.25).高さ(), 0.5);
    assert_eq!(鞍型の双一次の高さ(0.25, 0.75), 0.625);
    assert_eq!(鞍型の双一次の高さ(0.75, 0.25), 0.625);
}

#[test]
fn 傾きは選んだ三角形の辺の高さの差から出る() {
    let 奥側 = 鞍型の面(0.25, 0.75);
    assert_eq!(奥側.傾き().東の傾き(), -0.5);
    assert_eq!(奥側.傾き().南の傾き(), 0.5);
    let 手前側 = 鞍型の面(0.75, 0.25);
    assert_eq!(手前側.傾き().東の傾き(), 0.5);
    assert_eq!(手前側.傾き().南の傾き(), -0.5);
}

/// 四隅が同一平面に乗る升目では、区分線形と双一次はどちらも同じ平面を表すため値が一致する。
#[test]
fn 四隅が同一平面に乗る升目では双一次と同じ値になる() {
    let 四隅 = 升目の四隅の高さ::生成する(0.0, 1.0, 2.0, 3.0).unwrap();
    let 比 = 升目の中の比::生成する(0.25, 0.75).unwrap();
    let 面 = 四隅.地表の面を求める(比, 升目の一辺::生成する(1.0).unwrap()).unwrap();
    assert_eq!(面.高さ(), 1.75);
    assert_eq!(面.傾き().東の傾き(), 1.0);
    assert_eq!(面.傾き().南の傾き(), 2.0);
}

/// 四隅がそれぞれ受け付ける範囲にあっても、刻みが極端に細かい格子では高さの差を刻みで割った傾きが
/// 単精度の表せる範囲を越える。桁あふれで傾きが有限でなくなる升目を、面の生成が型付きエラーで拒むことを見る。
#[test]
fn 傾きが桁あふれする升目を型付きエラーで拒む() {
    let 上限 = 16_777_216.0_f32;
    let 四隅 = 升目の四隅の高さ::生成する(-上限, 0.0, 上限, 0.0).unwrap();
    let 比 = 升目の中の比::生成する(0.0_f32, 1.0).unwrap();
    assert_eq!(
        四隅.地表の面を求める(比, 升目の一辺::生成する(f32::MIN_POSITIVE).unwrap()),
        Err(升目の値の生成エラー::地表の面の高さか傾きが有限でない)
    );
}

/// 高さの絶対値の上限をわずかに越えた四隅を拒むことを見る。この上限が、隣り合う升目が共有辺の上で返す
/// 高さの差の上界を成り立たせている。
#[test]
fn 上限を越えた高さの四隅を型付きエラーで拒む() {
    let 上限を越えた高さ = 地表の高さの絶対値の上限メートル * 1.000_000_1;
    assert_eq!(
        升目の四隅の高さ::生成する(0.0, 上限を越えた高さ, 0.0, 0.0),
        Err(升目の値の生成エラー::四隅の高さの絶対値が上限を越えている)
    );
    assert!(升目の四隅の高さ::生成する(0.0, -地表の高さの絶対値の上限メートル, 0.0, 地表の高さの絶対値の上限メートル).is_ok());
}

#[test]
fn 壊れた入力を型付きエラーで拒む() {
    assert_eq!(
        升目の四隅の高さ::生成する(0.0, f64::NAN, 0.0, 0.0),
        Err(升目の値の生成エラー::四隅の高さが有限でない)
    );
    assert_eq!(升目の中の比::<f64>::生成する(1.5, 0.0), Err(升目の値の生成エラー::升目の中の比が範囲外));
    assert_eq!(升目の一辺::生成する(0.0_f64), Err(升目の値の生成エラー::升目の一辺が正の有限値でない));
}
