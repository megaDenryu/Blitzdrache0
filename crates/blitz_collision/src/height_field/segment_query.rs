//! 高さ場の線分の問い合わせ: 始点から終点へ引いた線分が高さ場の地表に最初に当たる点を求める操作サービス。
//! 四隅の高さの供給元と升目の一辺をコンストラクタで受け取って保持するため、問い合わせの署名に高さの並びも
//! 格子の刻みも現れない。
//!
//! 1回の問い合わせでヒープを確保しない。走査が持つのは2つの軸の状態だけであり、横断した升目を貯めずに
//! 1つずつ調べて捨てる。当たりが見つかった時点で走査を止めるため、調べる升目は当たりまでの升目だけである。

use super::axis_traversal::軸ごとの升目の横断;
use super::cell_edge::升目の一辺;
use super::cell_index::升目の格子添字;
use super::cell_segment_intersection::升目の中の線分の1次式;
use super::cell_traversal::{升目の横断の続き, 升目の横断の走査};
use super::corner_source::升目の四隅の高さの供給元;
use super::segment::高さ場を貫く線分;
use super::segment_error::線分の問い合わせエラー;
use super::segment_hit::地表への最初の当たり;
use super::segment_parameter::線分の媒介変数;
use super::segment_query_result::線分と高さ場の当たりの結果;

/// 高さ場の線分の問い合わせ。四隅の高さの供給元と升目の一辺を保持し、線分が最初に当たる点を答える操作サービスである。
pub struct 高さ場の線分の問い合わせ<'供給元, 供給元> {
    四隅の供給元: &'供給元 供給元,
    升目の一辺: 升目の一辺<f64>,
}

impl<'供給元, 供給元: 升目の四隅の高さの供給元> 高さ場の線分の問い合わせ<'供給元, 供給元> {
    /// 四隅の高さの供給元と升目の一辺を受け取って作る。
    pub fn 生成する(四隅の供給元: &'供給元 供給元, 升目の一辺: 升目の一辺<f64>) -> Self {
        Self {
            四隅の供給元, 升目の一辺
        }
    }

    /// 線分が高さ場の地表に最初に当たる点を求める。当たらない場合と、調べられない升目で打ち切った場合を
    /// 結果の2つの軸で区別する。
    pub fn 線分が地表に最初に当たる点を求める(
        &self,
        線分: &高さ場を貫く線分,
    ) -> Result<線分と高さ場の当たりの結果, 線分の問い合わせエラー> {
        let Some(mut 走査) = self.升目の横断の走査を始める(線分) else {
            return Ok(線分と高さ場の当たりの結果::当たらないまま調べられない升目で打ち切った());
        };
        let 天頂の1次式 = 線分.天頂のメートルの1次式();
        loop {
            let 升目 = match 走査.次の升目へ進む() {
                升目の横断の続き::次の升目(升目) => 升目,
                升目の横断の続き::線分の終わりに達した => {
                    return Ok(線分と高さ場の当たりの結果::当たらないまま線分の全体を調べた());
                }
                升目の横断の続き::升目の添字を表せなくなった => {
                    return Ok(線分と高さ場の当たりの結果::当たらないまま調べられない升目で打ち切った());
                }
            };
            let Some(四隅) = self.四隅の供給元.升目の四隅の高さを参照する(升目.添字()) else {
                return Ok(線分と高さ場の当たりの結果::当たらないまま調べられない升目で打ち切った());
            };
            let 升目の中の線分 = 升目の中の線分の1次式::生成する(升目.東の比の1次式(), 升目.南の比の1次式(), 天頂の1次式);
            let 当たり = 升目の中の線分.地表に最初に当たる点を求める(&四隅, self.升目の一辺, 升目.入る端(), 升目.出る端())?;
            let Some(当たり) = 当たり else {
                continue;
            };
            let 交差時刻 = 線分の媒介変数::端へ寄せて生成する(当たり.媒介変数())?;
            return Ok(線分と高さ場の当たりの結果::当たりを見つけた(
                地表への最初の当たり::生成する(交差時刻, 線分.線分上の点を求める(交差時刻)?, 当たり.地表の面(), 升目.添字()),
            ));
        }
    }

    // 線分の両端の水平位置を格子の実数添字へ直して走査を組む。添字として表せない位置は`None`を返し、
    // 呼び出し側は打ち切りとして扱う。
    fn 升目の横断の走査を始める(&self, 線分: &高さ場を貫く線分) -> Option<升目の横断の走査> {
        let 東の横断 = 軸ごとの升目の横断::生成する(
            self.升目の一辺.メートルを実数添字へ直す(線分.始点().東のメートル()),
            self.升目の一辺.メートルを実数添字へ直す(線分.終点().東のメートル()),
        )?;
        let 南の横断 = 軸ごとの升目の横断::生成する(
            self.升目の一辺.メートルを実数添字へ直す(線分.始点().南のメートル()),
            self.升目の一辺.メートルを実数添字へ直す(線分.終点().南のメートル()),
        )?;
        Some(self.供給元が答えられる最初の升目から走査を組む(東の横断, 南の横断))
    }

    // 走査の最初の升目を、供給元が答えられる升目へ寄せて走査を組む。
    //
    // 軸へ進まない線分の始点は升目の境界のちょうど上に載りうる。その点は境界の両側の升目に属し、どちらの
    // 添字で尋ねても同じ位置の高さを指すが、格子のいちばん外の縁では片方の升目しか実在しない。どちらが
    // 実在するかを知るのは格子の広がりを持つ供給元だけであるため、在りうる升目を順に尋ね、答えのある升目を
    // 走査の始まりにする。1つも答えが無ければ床の側で組み、走査がそのまま打ち切りとして伝える。
    // 参照: `crates/blitz_engine/src/height_field/cell_position.rs`が高さだけの問い合わせで置く縁の規約
    // (最後の格子点ちょうどは1つ手前の升目の右端)と同じ意味論であり、そちらは格子点数を持つため尋ねずに決める。
    fn 供給元が答えられる最初の升目から走査を組む(
        &self,
        東の横断: 軸ごとの升目の横断,
        南の横断: 軸ごとの升目の横断,
    ) -> 升目の横断の走査 {
        if 東の横断.境界の上に静止しているか() || 南の横断.境界の上に静止しているか() {
            for 東 in 東の横断.走査の始まりに在りうる横断を並べる() {
                for 南 in 南の横断.走査の始まりに在りうる横断を並べる() {
                    let 添字 = 升目の格子添字::生成する(東.現在の升目の添字(), 南.現在の升目の添字());
                    if self.四隅の供給元.升目の四隅の高さを参照する(添字).is_some() {
                        return 升目の横断の走査::生成する(東, 南);
                    }
                }
            }
        }
        升目の横断の走査::生成する(東の横断, 南の横断)
    }
}
