//! 升目の四隅の高さの供給元: 升目の格子添字を渡すと、その升目の四隅の高さを答える能力である。
//!
//! 衝突数学層は世界も高さ場のアセットも知らないため、高さの並びを自分では持たない。走査はこの能力へ升目を
//! 1つずつ尋ね、答えの無い升目に達した時点で打ち切る。コールバックでなく能力として置くのは、答える側が
//! 標本の並びという状態を持ち続けるものであり、その場で1回だけ実行される処理ではないためである。
//!
//! 前提: 答えを返す升目が有限個であること。すべての升目へ答える実装を渡すと、格子の外へ出た走査が終わらない。
//!
//! 前提: 答えられる升目の集合が矩形であること(凸であれば足りる)。線分が升目の角をちょうど通るとき、東と南の
//! 境界へ達する時刻は割り算の丸めで一致しないことがあり、そのときの走査は角に触れるだけの脇の升目を1つ経由する。
//! 集合に穴や切り欠きのある疎な供給元では、この脇の升目が答えられずに早期打ち切りが起きうる。矩形なら、
//! 角を共有する4つの升目のうち2つが答えられる限り残りも答えられるため、経由が害にならない。

use super::cell_corner_heights::升目の四隅の高さ;
use super::cell_index::升目の格子添字;

/// 升目の格子添字を渡すと、その升目の四隅の高さを答える能力。高さの並びと格子の広がりを持つ世界の側が実装する。
pub trait 升目の四隅の高さの供給元 {
    /// その升目の四隅の高さ。四隅のどれかが格子の広がりの外にある升目には`None`を返す。
    fn 升目の四隅の高さを参照する(&self, 添字: 升目の格子添字) -> Option<升目の四隅の高さ<f64>>;
}
