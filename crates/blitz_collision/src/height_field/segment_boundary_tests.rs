//! 線分が幾何の境目とちょうど重なる場合の反証。対角を越える時刻が升目に入る時刻・出る時刻と重なる線分、
//! 線分の全体が対角の上を走る線分、隣り合う2つの升目の共有辺のちょうど上に当たりが載る線分を見る。
//!
//! これらを分けて見るのは、ちょうど重なる場合だけ求解の区間の分け方が退化するためである。対角の片側の
//! 区間が幅0になり、その幅0の区間で三角形を選び損ねると面が変わる。共有辺の上の当たりは、手前の升目が
//! 取り逃すと同じ点を隣の升目が答えるため、当たった升目の添字まで見る。

#![allow(clippy::unwrap_used)]

use super::segment_query_fixture::{
    位置, 尾根がある地形を作る, 当たりを取り出す, 当たりを求める, 鞍型の地形を作る
};
use super::{升目の三角形, 線分の走査が調べた範囲};

// 東の比が南の比と等しくなる時刻が、升目に入る時刻とちょうど重なる線分。始点は升目の左手前の隅であり、
// そこから東が南の2倍の速さで進むため、対角を越える時刻は入る時刻に一致し、対角の手前側の区間が幅0になる。
// 幅0の区間が奥側の三角形で解かれ、残りの区間が手前側の三角形で解かれる。手前側の面の高さは東の比から
// 南の比を引いた値であり、天頂が1メートルから-0.5メートルへ下がる線分では交差時刻0.5で0.25メートルになる。
#[test]
fn 対角を越える時刻が入る時刻と重なる線分も正しく当たる() {
    let 結果 = 当たりを求める(&鞍型の地形を作る(), 1.0, 位置(0.0, 1.0, 0.0), 位置(1.0, -0.5, 0.5));
    assert_eq!(結果.調べた範囲(), 線分の走査が調べた範囲::線分の全体を調べた);
    let 当たり = 当たりを取り出す(結果);
    assert_eq!(当たり.交差時刻().値(), 0.5);
    assert_eq!(当たり.交差位置(), 位置(0.5, 0.25, 0.25));
    assert_eq!(当たり.地表の面().三角形(), 升目の三角形::手前側);
    assert_eq!(当たり.地表の面().高さ(), 0.25);
}

// 東の比が南の比と等しくなる時刻が、升目を出る時刻とちょうど重なる線分。升目の東の縁の中ほどから
// 右奥の角へ向かうため、対角を越える時刻は出る時刻に一致し、対角の奥側の区間が幅0になる。
#[test]
fn 対角を越える時刻が出る時刻と重なる線分も正しく当たる() {
    let 結果 = 当たりを求める(&鞍型の地形を作る(), 1.0, 位置(0.5, 1.0, 0.0), 位置(1.0, -0.5, 1.0));
    assert_eq!(結果.調べた範囲(), 線分の走査が調べた範囲::線分の全体を調べた);
    let 当たり = 当たりを取り出す(結果);
    assert_eq!(当たり.交差時刻().値(), 0.5);
    assert_eq!(当たり.交差位置(), 位置(0.75, 0.25, 0.5));
    assert_eq!(当たり.地表の面().三角形(), 升目の三角形::手前側);
    assert_eq!(当たり.地表の面().高さ(), 0.25);
}

// 線分の全体が対角の上を走る線分。東の比と南の比が常に等しいため対角を越える時刻は無く、区間は1つになり、
// 三角形は区間の中点で選んだ奥側になる。鞍型の升目の対角の上の高さはどこでも0メートルであり、
// 同じ点を双一次で混ぜた高さ(比0.5で0.5メートル)と見分けられる。
#[test]
fn 線分の全体が対角の上を走っても正しく当たる() {
    let 結果 = 当たりを求める(&鞍型の地形を作る(), 1.0, 位置(0.0, 1.0, 0.0), 位置(1.0, -1.0, 1.0));
    assert_eq!(結果.調べた範囲(), 線分の走査が調べた範囲::線分の全体を調べた);
    let 当たり = 当たりを取り出す(結果);
    assert_eq!(当たり.交差時刻().値(), 0.5);
    assert_eq!(当たり.交差位置(), 位置(0.5, 0.0, 0.5));
    assert_eq!(当たり.地表の面().三角形(), 升目の三角形::奥側);
    assert_eq!(当たり.地表の面().高さ(), 0.0);
}

// 尾根のてっぺん(2つの升目の共有辺の上)へちょうど当たる線分。天頂は2メートルから0メートルへ下がり、
// 地表は0.5メートルから1メートルへ上がるため、差が0になるのは東1メートル・天頂1メートルの尾根の点である。
// 当たった升目が手前の(0, 0)であることが、共有辺の上の当たりを手前の升目が取り逃していないことの反証である。
#[test]
fn 共有辺のちょうど上で地表に当たる() {
    let 結果 = 当たりを求める(&尾根がある地形を作る(), 1.0, 位置(0.5, 2.0, 0.5), 位置(1.5, 0.0, 0.5));
    assert_eq!(結果.調べた範囲(), 線分の走査が調べた範囲::線分の全体を調べた);
    let 当たり = 当たりを取り出す(結果);
    assert_eq!(当たり.交差時刻().値(), 0.5);
    assert_eq!(当たり.交差位置(), 位置(1.0, 1.0, 0.5));
    assert_eq!(当たり.升目の添字().東添字(), 0);
    assert_eq!(当たり.地表の面().高さ(), 1.0);
}
