//! 高さ場を貫く線分の問い合わせで破れる条件。走査は升目ごとに区分線形の面を組み直すため、升目の値の生成の
//! 破れもこの語彙へ畳み込む。
//!
//! 問い合わせが高さ場の広がりの外へ出たことはここに入らない。それは値が壊れたのではなく走査が線分の
//! どこまでを調べられたかの話であり、`線分の走査が調べた範囲`が別の軸で表す。

use thiserror::Error;

use super::error::升目の値の生成エラー;
use super::position_error::高さ場の位置の生成エラー;

/// 高さ場を貫く線分の問い合わせで破れる条件。線分の端点の位置・線分の媒介変数・線分が通る升目の値のそれぞれが守る条件である。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 線分の問い合わせエラー {
    /// 始点か終点を高さ場の格子原点からの位置として作れなかった。
    #[error("線分の端点の位置を作れない: {0}")]
    線分の端点の位置を作れない(#[from] 高さ場の位置の生成エラー),
    /// 線分の上の点を指す媒介変数が、0以上1以下の有限値でなかった。
    #[error("線分の媒介変数が0以上1以下の有限値でない")]
    線分の媒介変数が範囲外,
    /// 線分が通る升目の四隅の高さや地表の面を値として作れなかった。
    #[error("線分が通る升目の値を作れない: {0}")]
    升目の値を作れない(#[from] 升目の値の生成エラー),
}
