//! 升目の中で線分が地表に当たった点。媒介変数は升目の中ではなく線分の全体を0から1として測る。
//! 升目の走査が答えを返す途中の値であり、格子添字と線分上の位置を足した`地表への最初の当たり`とは別物である。

use super::ground_plane::升目の地表の面;

pub(super) struct 升目の中の当たり {
    媒介変数: f64,
    地表の面: 升目の地表の面<f64>,
}

impl 升目の中の当たり {
    pub(super) fn 生成する(媒介変数: f64, 地表の面: 升目の地表の面<f64>) -> Self {
        Self { 媒介変数, 地表の面 }
    }

    pub(super) fn 媒介変数(&self) -> f64 {
        self.媒介変数
    }

    pub(super) fn 地表の面(&self) -> 升目の地表の面<f64> {
        self.地表の面
    }
}
