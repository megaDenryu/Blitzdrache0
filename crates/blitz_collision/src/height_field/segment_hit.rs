//! 線分が高さ場の地表に最初に当たった点と、当たらなかったことを表す枝。
//!
//! 当たりが持つのは幾何学的な事実だけである。地面か壁か、そこで止まるか滑るかという意味付けは持たない。
//! 交差位置と地表の面の高さは同じ点を指す。前者は線分の上の点として、後者は升目の平面の上の点として求めた値であり、
//! どちらも同じ交差時刻から導いている。

use super::cell_index::升目の格子添字;
use super::grid_origin_position::高さ場の格子原点からの位置;
use super::ground_plane::升目の地表の面;
use super::segment_parameter::線分の媒介変数;

/// 線分が高さ場の地表に最初に当たった点。終点まで当たらなかった枝と、当たりを持つ枝の2つである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 線分が地表に最初に当たる点 {
    /// 終点まで地表に当たらなかった。
    地表に当たらない,
    /// 線分の途中で地表に当たり、その最初の当たりを持つ。
    地表に当たる(地表への最初の当たり),
}

/// 線分が地表に最初に当たった1つの事実。交差時刻・交差位置・そこの地表の面・升目の添字を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 地表への最初の当たり {
    交差時刻: 線分の媒介変数,
    交差位置: 高さ場の格子原点からの位置,
    地表の面: 升目の地表の面<f64>,
    升目の添字: 升目の格子添字,
}

impl 地表への最初の当たり {
    pub(super) fn 生成する(
        交差時刻: 線分の媒介変数,
        交差位置: 高さ場の格子原点からの位置,
        地表の面: 升目の地表の面<f64>,
        升目の添字: 升目の格子添字,
    ) -> Self {
        Self {
            交差時刻,
            交差位置,
            地表の面,
            升目の添字,
        }
    }

    /// 線分の始点を0、終点を1として測った、最初に地表へ達した時刻。始点が既に地表より下にある線分では0になる。
    pub fn 交差時刻(&self) -> 線分の媒介変数 {
        self.交差時刻
    }

    /// 線分の上の点として求めた交差の位置。地表の面の高さと同じ点を指す。
    pub fn 交差位置(&self) -> 高さ場の格子原点からの位置 {
        self.交差位置
    }

    /// 当たった点の地表の面。高さと2方向の傾きと、どちらの三角形の平面だったかを持つ。
    pub fn 地表の面(&self) -> 升目の地表の面<f64> {
        self.地表の面
    }

    /// 当たった三角形が属する升目の格子添字。
    pub fn 升目の添字(&self) -> 升目の格子添字 {
        self.升目の添字
    }
}
