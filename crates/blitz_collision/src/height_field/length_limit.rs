//! 高さ場の問い合わせが受け付ける長さの絶対値の上限。格子原点からの位置の成分・高さ場の中の変位の成分・
//! カプセルの半径がこの上限を守り、掃引が調べる升目の格子点の位置も同じ上限で検査する。
//!
//! 上限を課すのは、掃引の接触の2次方程式の係数と判別式が桁あふれしないことを保証するためである。
//! 保証が無いと、判別式が有限でなくなった枝が「根なし」へ写り、明白に面を横切る掃引が「覆いをすべて調べて
//! 触れなかった」として返る。指摘された反例は、軸の中心の高さが10の155乗メートル・半径1メートル・
//! 天頂の変位がマイナス10の155乗メートルの掃引であり、すべての候補が消えていた。
//! 高さ場を貫く線分の側に、答えを偽る同じ形の穴は無い。線分の求解は差と1つの割り算だけで書かれ、大きな2つの
//! 量の積を作らないためである。桁あふれしうるのは両端の天頂の差だけであり(片方が倍精度の最大値に近く、
//! もう片方がその符号違いのとき差が無限大になる)、そこから出る有限でない値は媒介変数と升目の中の比の検査が
//! 型付きエラーで止める。線分の端点も同じ位置の型を通るため、この上限がその入力を入口で拒む。
//!
//! 値が四隅の高さの絶対値の上限と同じ2の24乗メートルであるのは、格子点の位置の天頂の成分がその隅の高さ
//! そのものであり、2つの上限が食い違うと上限ちょうどの高さを持つ格子点が自分の位置を作れなくなるためである。
//! 2つの上限は根拠が別であり(高さの側は共有辺の上で隣り合う升目が返す高さの差の上界を導くための条件)、
//! 同じ値を選んだ理由がここにある。
//!
//! 桁あふれしないことの算術。上限をBと書く。三角形の頂点の位置・軸の端の位置・掃引の変位・半径はどれも
//! 成分の絶対値がB以下である。位置から位置を引いた変位は成分が2B以下であるから、三角形の辺の変位・軸の変位・
//! 掃引の始まりで三角形の頂点から軸の端へ向かう変位はどれも成分が2B以下である。係数を組むのに使うのは
//! 掃引の始まりすなわち時刻0の値だけであり、根の時刻で最近接を求め直す経路の値は係数にも判別式にも入らない。
//! 成分がX以下の変位と成分がY以下の変位について、内積は3つの積の和であるから3XY以下、外積は各成分が
//! 2つの積の差であるから成分が2XY以下である。以下では2次方程式を「2次の係数かける時刻の二乗、1次の係数かける
//! 時刻、定数項」の形で数え、判別式を1次の係数の二乗から4かける2次の係数かける定数項を引いたものとして数える。
//!
//! 候補は5種類ある。以下では係数の次数が低いものから順に数える。
//! 頂点と軸の端の式は、始まりの変位が2B以下・掃引の変位がB以下であるから、2次の係数が3Bの2乗以下・
//! 1次の係数が12Bの2乗以下・定数項が13Bの2乗以下であり、判別式は300Bの4乗以下である。
//! 面と軸の端の式は、内積の相手が成分1以下の上向きの単位法線であるから、始まりの隔たりが6B以下・
//! 隔たりの速度が3B以下であり、2次の係数が9Bの2乗以下・1次の係数が36Bの2乗以下・定数項が37Bの2乗以下、
//! 判別式は2628Bの4乗以下である。
//! 辺と軸の端の式は、外積と内積の相手が辺の変位であるから、始まりの外積が成分8Bの2乗以下・速度の外積が
//! 成分4Bの2乗以下・辺の長さの二乗が12Bの2乗以下であり、2次の係数が48Bの4乗以下・1次の係数が192Bの4乗以下・
//! 定数項が204Bの4乗以下、判別式は76032Bの8乗以下である。
//! 頂点と軸の内側の式は、辺の変位を軸の変位に取り替えただけの同じ形であるから、上界も同じである。
//!
//! 最大の次数になるのは辺と軸の内側の式である。この式だけは内積の相手が変位そのものでなく2つの変位の外積で
//! あり、そのぶん次数が2つ上がる。両方に垂直な向きは軸の変位と辺の変位の外積であるから成分が8Bの2乗以下、
//! その長さの二乗は192Bの4乗以下である。始まりの射影は2B以下の変位とこの向きの内積であるから48Bの3乗以下、
//! 射影の速度はB以下の掃引の変位とこの向きの内積であるから24Bの3乗以下である。したがって2次の係数は
//! 576Bの6乗以下、1次の係数は2304Bの6乗以下、定数項は始まりの射影の二乗2304Bの6乗と半径の二乗かける
//! 向きの長さの二乗192Bの6乗の和で2496Bの6乗以下である。判別式は、1次の係数の二乗が5308416Bの12乗以下、
//! 4かける2次の係数かける定数項が5750784Bの12乗以下であるから、和で11059200Bの12乗以下になる。
//!
//! B = 2の24乗ではBの12乗が2の288乗すなわちおよそ4.97かける10の86乗であるから、判別式の上界はおよそ
//! 5.5かける10の93乗である。これは倍精度の最大値1.8かける10の308乗の10のマイナス214乗倍を下回る。
//! 上限ちょうどの入力で最大の次数の式を組み、係数と判別式が倍精度に収まって手で解いた根が返ることの反証は
//! `crates/blitz_collision/src/height_field/capsule_sweep/length_limit_arithmetic_tests.rs` にある。
//! 参照: `crates/blitz_collision/src/height_field/capsule_sweep/solve_edge_axis.rs`
//!
//! 注意: 升目の格子点の水平の成分は升目の添字と升目の一辺の積であるから、一辺の大きい高さ場では上限を
//! 越えうる。上の算術は格子点もB以下であることを使うため、越えた格子点を持つ升目は答えられない値として
//! 型付きエラーで拒む(`crates/blitz_collision/src/height_field/capsule_sweep/surface_triangle.rs`)。
//! 一辺が2の24乗メートルに迫る高さ場は地形として在りえないため、実際の地形でこの縁に達しない。

/// 高さ場の問い合わせが受け付ける長さの絶対値の上限であるメートル。2の24乗であり、地球の半径のおよそ2.6倍である。
pub const 高さ場の問い合わせが受け付ける長さの絶対値の上限メートル: f64 = 16_777_216.0;
