//! 隣り合う2つの升目が共有する辺の上での一致の反証。走査が境界の比として渡す値と、2つの升目が返す高さの
//! 差の2つを見る。
//!
//! 分けて見るのは、共有辺の上で片側だけが地表より上と判定されると線分が地表を突き抜けるためである。
//! 比を1次式で求め直すと、始点からその境界までに横断した升目の数に比例して誤差が育つ。境界を横断した軸の
//! 比を走査が正準値として持つことでその誤差が消えることと、残る差が判断7の導いた上界に収まることを見る。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断7: 高さ場の物理は最詳細段の三角形化と一致させる」

#![allow(clippy::unwrap_used)]

use super::axis_traversal::軸ごとの升目の横断;
use super::cell_traversal::{升目の横断の続き, 升目の横断の走査};
use super::linear_in_parameter::媒介変数の1次式;
use super::{升目の一辺, 升目の中の比, 升目の四隅の高さ, 地表の高さの絶対値の上限メートル};

/// codexのレビューが挙げた反例の東の実数添字。この2つの値を結ぶ線分は88升目ぶん進み、添字19649の境界の上の
/// 比を1次式で求め直すと零からずれる。
const 反例の始点の東の実数添字: f64 = 19_704.200_921_507_865;
const 反例の終点の東の実数添字: f64 = 19_615.889_565_334_084;
const 反例の境界の東添字: i32 = 19649;

fn 反例の走査を組む() -> 升目の横断の走査 {
    let 東の横断 = 軸ごとの升目の横断::生成する(反例の始点の東の実数添字, 反例の終点の東の実数添字).unwrap();
    let 南の横断 = 軸ごとの升目の横断::生成する(0.5, 0.5).unwrap();
    升目の横断の走査::生成する(東の横断, 南の横断)
}

/// 添字19649の升目を出る比が厳密な零、隣の升目に入る比が厳密な一であることを見る。
/// 走査が境界の比を正準値として持っていることの反証である。
#[test]
fn 遠くの境界を越える升目の出る比と入る比は厳密な零と一になる() {
    let mut 走査 = 反例の走査を組む();
    let mut 出る比 = None;
    let mut 入る比 = None;
    loop {
        let 升目の横断の続き::次の升目(升目) = 走査.次の升目へ進む() else {
            break;
        };
        if 升目.添字().東添字() == 反例の境界の東添字 {
            出る比 = Some(升目.出る端().東の比を求める(升目.東の比の1次式()));
        }
        if 升目.添字().東添字() == 反例の境界の東添字 - 1 {
            入る比 = Some(升目.入る端().東の比を求める(升目.東の比の1次式()));
            break;
        }
    }
    assert_eq!(出る比, Some(0.0));
    assert_eq!(入る比, Some(1.0));
}

/// 正準値を持たなければ何が起きるかの反証。同じ境界の同じ時刻を比の1次式で求め直すと、
/// 大きな2項の相殺で残った誤差により、厳密な零でなく1の32ULPにあたる値を返す。
#[test]
fn 比の1次式で求め直すと遠くの境界で零からずれる() {
    let 実数添字の速度 = 反例の終点の東の実数添字 - 反例の始点の東の実数添字;
    let 境界へ達する時刻 = (f64::from(反例の境界の東添字) - 反例の始点の東の実数添字) / 実数添字の速度;
    let 比の1次式 = 媒介変数の1次式::生成する(反例の始点の東の実数添字 - f64::from(反例の境界の東添字), 実数添字の速度);
    assert_eq!(比の1次式.値を求める(境界へ達する時刻), 7.105_427_357_601_002e-15);
}

/// 東の縁を共有する2つの升目。西の升目の手前右と奥右が、東の升目の手前左と奥左と同じ格子点である。
fn 東の縁を共有する2つの升目(隅の高さ: [f64; 6]) -> (升目の四隅の高さ<f64>, 升目の四隅の高さ<f64>) {
    let [西の手前左, 共有する手前, 西の奥左, 共有する奥, 東の手前右, 東の奥右] = 隅の高さ;
    (
        升目の四隅の高さ::生成する(西の手前左, 共有する手前, 西の奥左, 共有する奥).unwrap(),
        升目の四隅の高さ::生成する(共有する手前, 東の手前右, 共有する奥, 東の奥右).unwrap(),
    )
}

/// 上限いっぱいの高さと、指数が大きく離れた高さを混ぜた並び。指数が離れると隅の差の減算に丸めが入るため、
/// 差が0のままにならない組を含める。3つ目と4つ目は差が1メートル掛ける丸めの単位まで出る組である。
fn 検査する隅の高さの並び() -> [[f64; 6]; 4] {
    let 上限 = 地表の高さの絶対値の上限メートル;
    [
        [上限, -上限, 上限 * 0.5, -上限 * 0.25, 上限, -上限],
        [1.0, -上限, 0.5, 上限, -1.0, 2.0],
        [
            1_009_464.390_069_665_4,
            -16_485_798.705_267_262,
            -0.008_604_280_378_376_149,
            -3.872_951_832_547_798_3,
            0.000_183_680_641_544_563_98,
            -2.411_427_560_022_025e-5,
        ],
        [
            61_629.870_757_872_25,
            -16_733_996.971_391_086,
            -0.015_705_772_616_822_086,
            -3_818.970_845_493_273_4,
            -0.027_840_294_628_268_425,
            1.453_207_509_841_336_2,
        ],
    ]
}

/// 共有辺の上で西の升目は東の比一、東の升目は東の比零を受け取る。どちらも辺に沿った南の比は同じ値である。
#[test]
fn 共有辺の上で隣り合う升目が返す高さの差は判断7の上界に収まる() {
    let 一辺 = 升目の一辺::生成する(1.0).unwrap();
    let 上界 = 12.0 * 地表の高さの絶対値の上限メートル * (f64::EPSILON * 0.5);
    for 隅の高さ in 検査する隅の高さの並び() {
        let (西の升目, 東の升目) = 東の縁を共有する2つの升目(隅の高さ);
        for 南の比 in [0.0, 0.25, 1.0 / 3.0, 0.7, 1.0] {
            let 西の縁 = 升目の中の比::生成する(1.0, 南の比).unwrap();
            let 東の縁 = 升目の中の比::生成する(0.0, 南の比).unwrap();
            let 西の高さ = 西の升目.地表の面を求める(西の縁, 一辺).unwrap().高さ();
            let 東の高さ = 東の升目.地表の面を求める(東の縁, 一辺).unwrap().高さ();
            assert!(
                (西の高さ - 東の高さ).abs() <= 上界,
                "南の比{南の比}で共有辺の差が上界を越えた: {西の高さ}と{東の高さ}"
            );
        }
    }
}
