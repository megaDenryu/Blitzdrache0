//! 升目の四隅の高さ。手前が南の添字、奥が南の添字の次であり、左が東の添字、右が東の添字の次である。
//! 区分線形の面を求める操作をこの型が持つのは、どの隅がどの三角形の頂点になるかがこの4つの並びの意味だからである。
//!
//! 高さだけを要る呼び出しも同じ1つの工程を通す。三角形の選び方と平面の式を2つ持つと、高さを求めた三角形と
//! 傾きを求めた三角形が食い違い、面に乗っていない値が生まれる。
//!
//! 高さの絶対値に上限を課すのは、隣り合う2つの升目が共有辺の上で返す高さの差を抑えるためである。共有辺の上では
//! 両側の式が数学的に同じ値を与えるが、浮動小数点では一致しない。差の上界は関わる隅の高さの絶対値に比例するため、
//! 上限が無ければ差はメートル級にもなりうる(手前左が-3かける10の38乗、手前右が1のとき、手前左に手前右と手前左の差を
//! 足した値は0になり、共有辺の上で片側が0・隣が1を返してちょうど1メートルずれる)。上限を2の24乗メートルへ置くと、
//! 差は隅の高さの絶対値の最大と倍精度の丸めの単位の積の12倍以下、すなわち0.03マイクロメートル未満に収まり、
//! 地表とちょうど接する線分の当たりを取り逃す幅もそこまでに限られる。この上界は、辺を横切る軸の比が厳密に0と1であり、
//! 辺に沿った軸の比が両側で同じ倍精度の値であることを前提にする。前者を与えるのが`cell_interval_end.rs`の正準値である。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断7: 高さ場の物理は最詳細段の三角形化と一致させる」の導出

use super::cell_corner::升目の隅;
use super::cell_edge::升目の一辺;
use super::cell_ratio::升目の中の比;
use super::error::升目の値の生成エラー;
use super::ground_plane::升目の地表の面;
use super::real::地表の平面の実数;
use super::slope::地表の傾き;
use super::triangle::升目の三角形;

/// 升目の四隅の高さとして受け付ける絶対値の上限であるメートル。2の24乗であり、単精度がこの値までは
/// 1メートル刻みの整数をすべて表せる。地球の半径のおよそ2.6倍であり、地形の高さとして在りうる範囲を上回る。
pub const 地表の高さの絶対値の上限メートル: f64 = 16_777_216.0;

/// 升目を囲む4つの格子点の高さ。並びの意味は手前左・手前右・奥左・奥右である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 升目の四隅の高さ<数> {
    手前左: 数,
    手前右: 数,
    奥左: 数,
    奥右: 数,
}

impl<数: 地表の平面の実数> 升目の四隅の高さ<数> {
    /// 四隅の高さが有限でありその絶対値が上限に収まることを確かめて作る。
    pub fn 生成する(手前左: 数, 手前右: 数, 奥左: 数, 奥右: 数) -> Result<Self, 升目の値の生成エラー> {
        if [手前左, 手前右, 奥左, 奥右].into_iter().any(|高さ| !高さ.有限か()) {
            return Err(升目の値の生成エラー::四隅の高さが有限でない);
        }
        if [手前左, 手前右, 奥左, 奥右]
            .into_iter()
            .any(|高さ| 高さ.倍精度へ広げる().abs() > 地表の高さの絶対値の上限メートル)
        {
            return Err(升目の値の生成エラー::四隅の高さの絶対値が上限を越えている);
        }
        Ok(Self {
            手前左, 手前右, 奥左, 奥右
        })
    }

    /// 名前で指した隅の高さ。掃引の接触が三角形の頂点で起きたとき、その頂点の位置をこの高さから組む。
    pub fn 隅の高さ(&self, 隅: 升目の隅) -> 数 {
        match 隅 {
            升目の隅::手前左 => self.手前左,
            升目の隅::手前右 => self.手前右,
            升目の隅::奥左 => self.奥左,
            升目の隅::奥右 => self.奥右,
        }
    }

    /// 升目の中の1点で、描画が実際に張る三角形の平面を読む。傾きは選んだ三角形の2辺の高さの差から導くため、
    /// 高さと傾きが必ず同じ平面のものになる。
    ///
    /// 四隅がそれぞれ有限でも高さの差は浮動小数点の表せる範囲を越えうるため、面を組む`升目の地表の面::生成する`が
    /// 導いた高さと2方向の傾きの有限性を検査し、破れていれば型付きエラーを返す。
    pub fn 地表の面を求める(
        &self,
        比: 升目の中の比<数>,
        一辺: 升目の一辺<数>,
    ) -> Result<升目の地表の面<数>, 升目の値の生成エラー> {
        self.指定した三角形の地表の面を求める(比.属する三角形を求める(), 比, 一辺)
    }

    // 三角形を呼び出し側が指定して平面を読む。線分の走査が対角の片側の区間を解くときに要る。
    // 区間の端がちょうど対角の上に載ると、その点の比から選ぶ三角形が区間の内側の三角形と食い違い、
    // 1つの区間の両端が別々の平面の値になってしまうためである。
    pub(super) fn 指定した三角形の地表の面を求める(
        &self,
        三角形: 升目の三角形,
        比: 升目の中の比<数>,
        一辺: 升目の一辺<数>,
    ) -> Result<升目の地表の面<数>, 升目の値の生成エラー> {
        let (高さ, 東の高さの差, 南の高さの差) = match 三角形 {
            升目の三角形::奥側 => (self.奥側の三角形の高さ(比), self.奥右 - self.奥左, self.奥左 - self.手前左),
            升目の三角形::手前側 => (self.手前側の三角形の高さ(比), self.手前右 - self.手前左, self.奥右 - self.手前右),
        };
        let 傾き = 地表の傾き::生成する(一辺.高さの差を傾きへ直す(東の高さの差), 一辺.高さの差を傾きへ直す(南の高さの差));
        升目の地表の面::生成する(高さ, 傾き, 三角形)
    }

    // 対角より奥側にある三角形、すなわち手前左・奥左・奥右を頂点に持つ面の高さ。
    // 3頂点でそれぞれの隅の値になり、比の1次式であるため面そのものを表す。
    fn 奥側の三角形の高さ(&self, 比: 升目の中の比<数>) -> 数 {
        self.手前左 + (self.奥左 - self.手前左) * 比.南の比() + (self.奥右 - self.奥左) * 比.東の比()
    }

    // 対角より手前側にある三角形、すなわち手前左・手前右・奥右を頂点に持つ面の高さ。
    // 対角の上では2つの式が数学的には同じ値を与えるため、面は対角で途切れない。浮動小数点では一致せず、
    // その差は与えた2つの比の差に比例する。共有辺の差とは別の量である。
    // 参照: `_doc/設計/世界の形と衝突基盤.md`「判断7」の「升目の中の対角の上の跳び」
    fn 手前側の三角形の高さ(&self, 比: 升目の中の比<数>) -> 数 {
        self.手前左 + (self.手前右 - self.手前左) * 比.東の比() + (self.奥右 - self.手前右) * 比.南の比()
    }
}
