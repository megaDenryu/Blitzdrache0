//! 升目1つの中で、線分と地表の三角形の平面が最初に交わる媒介変数を解く工程。
//!
//! 升目の中では地表は2つの三角形の平面であり、線分の高さと地表の高さの差は対角をまたぐ点で区切った区間ごとに
//! 媒介変数の1次式になる。区間ごとに1次方程式を1回解くだけで交差の時刻が確定するため、数値の刻み探索も
//! 二分法も使わない。同じ入力が必ず同じ結果を返すこと(判断14)と、升目の縁でも誤差が積み上がらないことが理由である。

use super::cell_corner_heights::升目の四隅の高さ;
use super::cell_edge::升目の一辺;
use super::cell_hit::升目の中の当たり;
use super::cell_interval_end::升目に居る区間の端;
use super::cell_ratio::升目の中の比;
use super::linear_in_parameter::媒介変数の1次式;
use super::segment_error::線分の問い合わせエラー;

/// 升目の中に居る間の線分を、媒介変数の1次式3本で表したもの。東と南は升目の中の比、天頂はメートルである。
#[derive(Debug, Clone, Copy)]
pub(super) struct 升目の中の線分の1次式 {
    東の比: 媒介変数の1次式,
    南の比: 媒介変数の1次式,
    天頂のメートル: 媒介変数の1次式,
}

impl 升目の中の線分の1次式 {
    pub(super) fn 生成する(
        東の比: 媒介変数の1次式, 南の比: 媒介変数の1次式, 天頂のメートル: 媒介変数の1次式
    ) -> Self {
        Self {
            東の比,
            南の比,
            天頂のメートル,
        }
    }

    /// 升目に居る区間の中で、線分が地表へ最初に達する点を求める。区間の始まりで既に地表より下に居る場合は、
    /// その始まりの時刻を当たりとして返す。線分の始点が地表の下にあるときの交差時刻が0になるのはこの定めによる。
    pub(super) fn 地表に最初に当たる点を求める(
        &self,
        四隅: &升目の四隅の高さ<f64>,
        一辺: 升目の一辺<f64>,
        入る端: 升目に居る区間の端,
        出る端: 升目に居る区間の端,
    ) -> Result<Option<升目の中の当たり>, 線分の問い合わせエラー> {
        let 対角を越える時刻 = self.対角を越える時刻を求める(入る端, 出る端);
        let 手前の区間の終わり = 対角を越える時刻.map_or(出る端, 升目に居る区間の端::升目の内側の時刻から生成する);
        if let Some(当たり) = self.対角の片側の区間で当たる点を求める(四隅, 一辺, 入る端, 手前の区間の終わり)? {
            return Ok(Some(当たり));
        }
        let Some(奥の区間の始まり) = 対角を越える時刻 else {
            return Ok(None);
        };
        let 奥の区間の始まりの端 = 升目に居る区間の端::升目の内側の時刻から生成する(奥の区間の始まり);
        self.対角の片側の区間で当たる点を求める(四隅, 一辺, 奥の区間の始まりの端, 出る端)
    }

    /// 対角をまたがない1つの区間で、線分の高さと地表の高さの差の1次式を解く。
    /// 三角形を区間の中点で1度だけ選んで両端に使うのは、区間の端がちょうど対角の上に載ると、
    /// 比から選ぶ三角形が区間の内側の三角形と食い違うためである。
    fn 対角の片側の区間で当たる点を求める(
        &self,
        四隅: &升目の四隅の高さ<f64>,
        一辺: 升目の一辺<f64>,
        始まりの端: 升目に居る区間の端,
        終わりの端: 升目に居る区間の端,
    ) -> Result<Option<升目の中の当たり>, 線分の問い合わせエラー> {
        let 中点の時刻 = (始まりの端.時刻() + 終わりの端.時刻()) * 0.5;
        let 三角形 = self.升目の内側の時刻の比を求める(中点の時刻)?.属する三角形を求める();
        let 始まりの面 = 四隅.指定した三角形の地表の面を求める(三角形, self.区間の端の比を求める(始まりの端)?, 一辺)?;
        let 始まりの差 = self.天頂のメートル.値を求める(始まりの端.時刻()) - 始まりの面.高さ();
        if 始まりの差 <= 0.0 {
            return Ok(Some(升目の中の当たり::生成する(始まりの端.時刻(), 始まりの面)));
        }
        let 終わりの面 = 四隅.指定した三角形の地表の面を求める(三角形, self.区間の端の比を求める(終わりの端)?, 一辺)?;
        let 終わりの差 = self.天頂のメートル.値を求める(終わりの端.時刻()) - 終わりの面.高さ();
        if 終わりの差 > 0.0 {
            return Ok(None);
        }
        // 始まりの差は正、終わりの差は0以下であるから、この割り算の分母は必ず正である。
        let 区間の幅 = 終わりの端.時刻() - 始まりの端.時刻();
        let 媒介変数 = 始まりの端.時刻() + 区間の幅 * (始まりの差 / (始まりの差 - 終わりの差));
        let 地表の面 = 四隅.指定した三角形の地表の面を求める(三角形, self.升目の内側の時刻の比を求める(媒介変数)?, 一辺)?;
        Ok(Some(升目の中の当たり::生成する(媒介変数, 地表の面)))
    }

    /// 区間の中で東の比と南の比が入れ替わる時刻。入れ替わらないなら`None`を返す。この時刻を境に、
    /// 点が属する三角形が変わる。区間の端の比は、面の高さを求めるときと同じ値を使う。
    fn 対角を越える時刻を求める(
        &self, 始まりの端: 升目に居る区間の端, 終わりの端: 升目に居る区間の端
    ) -> Option<f64> {
        let 入る時の差 = 始まりの端.東の比を求める(self.東の比) - 始まりの端.南の比を求める(self.南の比);
        let 出る時の差 = 終わりの端.東の比を求める(self.東の比) - 終わりの端.南の比を求める(self.南の比);
        if (入る時の差 > 0.0) == (出る時の差 > 0.0) {
            return None;
        }
        let 始まりの時刻 = 始まりの端.時刻();
        let 越える時刻 = 始まりの時刻 + (終わりの端.時刻() - 始まりの時刻) * (入る時の差 / (入る時の差 - 出る時の差));
        Some(越える時刻.clamp(始まりの時刻, 終わりの端.時刻()))
    }

    fn 区間の端の比を求める(&self, 端: 升目に居る区間の端) -> Result<升目の中の比<f64>, 線分の問い合わせエラー> {
        Ok(升目の中の比::縁へ寄せて生成する(
            端.東の比を求める(self.東の比),
            端.南の比を求める(self.南の比),
        )?)
    }

    /// 区間の内側の時刻での比。対角を越える時刻と当たりの時刻がこれであり、縁の上の正準値を持たない。
    fn 升目の内側の時刻の比を求める(&self, 時刻: f64) -> Result<升目の中の比<f64>, 線分の問い合わせエラー> {
        self.区間の端の比を求める(升目に居る区間の端::升目の内側の時刻から生成する(時刻))
    }
}
