//! 升目の地表の面: 升目の中の1点で読んだ、描画が実際に張る三角形の平面である。
//! 持つのは高さと2方向の傾きと、どちらの三角形から来たかであり、格子のどこにある升目かは持たない。
//! 升目の位置を知るのは問い合わせた側であり、この型は升目1つの中だけを知る。
//!
//! 高さを生の実数で返すのは、対応する単位型が単精度(メートル)と倍精度(大域メートル)で別の型であり、
//! どちらへ写すかを呼び出し側が決めるためである。ここがこの層の生値の境界である。
//!
//! 高さと傾きが有限であることをこの型が保つ。四隅と升目の一辺がそれぞれ検査済みでも、四隅の高さの差は
//! 浮動小数点の表せる範囲を越えうるためである。

use super::error::升目の値の生成エラー;
use super::real::地表の平面の実数;
use super::slope::地表の傾き;
use super::triangle::升目の三角形;

/// 升目の中の1点で読んだ、描画が実際に張る三角形の平面。高さと2方向の傾きと、どちらの三角形から来たかを持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 升目の地表の面<数> {
    高さ: 数,
    傾き: 地表の傾き<数>,
    三角形: 升目の三角形,
}

impl<数: 地表の平面の実数> 升目の地表の面<数> {
    /// 桁あふれで有限でなくなった高さ・傾きを拒む。ここで止めないと、面に乗っていない足元や
    /// 成分が有限でない法線が、検査を1つも通らずに呼び出し側へ渡る。
    pub fn 生成する(高さ: 数, 傾き: 地表の傾き<数>, 三角形: 升目の三角形) -> Result<Self, 升目の値の生成エラー> {
        if [高さ, 傾き.東の傾き(), 傾き.南の傾き()].into_iter().any(|値| !値.有限か()) {
            return Err(升目の値の生成エラー::地表の面の高さか傾きが有限でない);
        }
        Ok(Self { 高さ, 傾き, 三角形 })
    }

    /// その点の地表の高さ。単位は呼び出し側が決めるためこの層では生の実数で返す。
    pub fn 高さ(&self) -> 数 {
        self.高さ
    }

    /// その平面の東と南の傾き。
    pub fn 傾き(&self) -> 地表の傾き<数> {
        self.傾き
    }

    /// その点が属するのが升目のどちらの三角形か。
    pub fn 三角形(&self) -> 升目の三角形 {
        self.三角形
    }
}
