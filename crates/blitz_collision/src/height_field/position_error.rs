//! 高さ場の格子原点を基準にした位置と変位を作るときに破れる条件。
//!
//! 線分の問い合わせの語彙にもカプセルの掃引の語彙にも属さない別の型にするのは、位置と変位がどちらの
//! 問い合わせにも現れる共通の値であり、片方の失敗の語彙に属させると、もう片方が他方の名前を借りるためである。
//! どちらの問い合わせの語彙もこの型を`#[from]`で畳み込む。

use thiserror::Error;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 高さ場の位置の生成エラー {
    #[error("高さ場の格子原点からの位置の成分に有限でない値が含まれる")]
    位置の成分が有限でない,
    #[error("高さ場の格子原点からの位置の成分の絶対値が上限を越えている")]
    位置の成分の絶対値が上限を越えている,
    #[error("高さ場の中の変位の成分に有限でない値が含まれる")]
    変位の成分が有限でない,
    #[error("高さ場の中の変位の成分の絶対値が上限を越えている")]
    変位の成分の絶対値が上限を越えている,
}
