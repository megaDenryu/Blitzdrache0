//! 高さ場の中の変位: 高さ場の格子原点を基準にした2つの位置の差である。成分の並びは東・天頂・南であり、
//! 単位はメートル、精度は倍精度である。
//!
//! 位置と別の型にするのは、位置どうしの加算に意味が無く、位置から位置を引いた量だけが向きと長さを持つためである。
//! 内積・外積・長さの二乗をこの型が持つのは、掃引の接触の求解がこの3つと定数倍だけで書けるからであり、
//! 3つの成分を裸で持ち回すと東と南を取り違えても型が通るためである。
//!
//! 演算の結果は有限性を検査し直さない。生成の検査が成分の絶対値を上限に収めており、その上限から
//! 内積・外積・実数倍を重ねた掃引の係数と判別式が倍精度の範囲を出ないことを算術で示せるためである。
//! 上限とその算術は `crates/blitz_collision/src/height_field/length_limit.rs` にある。

use super::length_limit::高さ場の問い合わせが受け付ける長さの絶対値の上限メートル;
use super::position_error::高さ場の位置の生成エラー;
use super::unit_direction::地表の単位向き;

/// 高さ場の格子原点を基準にした2つの位置の差。成分の並びは東・天頂・南であり、単位はメートルである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 高さ場の中の変位 {
    東のメートル: f64,
    天頂のメートル: f64,
    南のメートル: f64,
}

impl 高さ場の中の変位 {
    /// 成分が有限でありその絶対値が上限に収まることを確かめて作る。
    pub fn 生成する(
        東のメートル: f64, 天頂のメートル: f64, 南のメートル: f64
    ) -> Result<Self, 高さ場の位置の生成エラー> {
        if [東のメートル, 天頂のメートル, 南のメートル].into_iter().any(|値| !値.is_finite()) {
            return Err(高さ場の位置の生成エラー::変位の成分が有限でない);
        }
        if [東のメートル, 天頂のメートル, 南のメートル]
            .into_iter()
            .any(|値| 値.abs() > 高さ場の問い合わせが受け付ける長さの絶対値の上限メートル)
        {
            return Err(高さ場の位置の生成エラー::変位の成分の絶対値が上限を越えている);
        }
        Ok(Self::演算の結果から組む(東のメートル, 天頂のメートル, 南のメートル))
    }

    pub(super) fn 演算の結果から組む(東のメートル: f64, 天頂のメートル: f64, 南のメートル: f64) -> Self {
        Self {
            東のメートル,
            天頂のメートル,
            南のメートル,
        }
    }

    // 単位向きを同じ成分の変位として読む。丸めを1つも通さないため、面の法線を求め直しても向きが動かない。
    pub(super) fn 単位向きから読む(向き: 地表の単位向き<f64>) -> Self {
        Self::演算の結果から組む(向き.東成分(), 向き.天頂成分(), 向き.南成分())
    }

    /// 東向きの成分であるメートル。
    pub fn 東のメートル(&self) -> f64 {
        self.東のメートル
    }

    /// 天頂向きの成分であるメートル。
    pub fn 天頂のメートル(&self) -> f64 {
        self.天頂のメートル
    }

    /// 南向きの成分であるメートル。
    pub fn 南のメートル(&self) -> f64 {
        self.南のメートル
    }

    pub(super) fn 加える(self, 相手: Self) -> Self {
        Self::演算の結果から組む(
            self.東のメートル + 相手.東のメートル,
            self.天頂のメートル + 相手.天頂のメートル,
            self.南のメートル + 相手.南のメートル,
        )
    }

    pub(super) fn 引く(self, 相手: Self) -> Self {
        Self::演算の結果から組む(
            self.東のメートル - 相手.東のメートル,
            self.天頂のメートル - 相手.天頂のメートル,
            self.南のメートル - 相手.南のメートル,
        )
    }

    pub(super) fn 実数倍する(self, 倍率: f64) -> Self {
        Self::演算の結果から組む(self.東のメートル * 倍率, self.天頂のメートル * 倍率, self.南のメートル * 倍率)
    }

    pub(super) fn 内積(self, 相手: Self) -> f64 {
        self.東のメートル * 相手.東のメートル + self.天頂のメートル * 相手.天頂のメートル + self.南のメートル * 相手.南のメートル
    }

    pub(super) fn 外積(self, 相手: Self) -> Self {
        Self::演算の結果から組む(
            self.天頂のメートル * 相手.南のメートル - self.南のメートル * 相手.天頂のメートル,
            self.南のメートル * 相手.東のメートル - self.東のメートル * 相手.南のメートル,
            self.東のメートル * 相手.天頂のメートル - self.天頂のメートル * 相手.東のメートル,
        )
    }

    pub(super) fn 長さの二乗(self) -> f64 {
        self.内積(self)
    }

    // 長さを1に正した向き。長さが0または有限でない変位は向きを持たないため`None`を返す。
    // 呼び出し側は、接触の隔たりが0のときに代わりの向き(地表の上向きの単位法線)を選ぶ。
    pub(super) fn 長さで正した単位向きを求める(self) -> Option<地表の単位向き<f64>> {
        if !self.長さの二乗().is_finite() || self.長さの二乗() <= 0.0 {
            return None;
        }
        Some(地表の単位向き::正して生成する(
            self.東のメートル,
            self.天頂のメートル,
            self.南のメートル,
        ))
    }
}
