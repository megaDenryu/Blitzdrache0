//! 三角形網の階層の構築: 三角形ごとの境界を受け取り、境界の木を1本組み上げる操作サービスである。
//!
//! 呼び出しタイミング: 三角形網を生成するときの1回だけである。実行中に組み直すことはない
//! (`_doc/設計/世界の形と衝突基盤.md`「判断11: 静的衝突メッシュは階層を持ち、事前生成を基本とする」の
//! 不変条件3)。
//!
//! 組み立ての途中の状態(まだ子の位置が決まっていない節点、まだ並べ替えの済んでいない範囲)をこの型が引き受け、
//! 完成した木にはその半端な状態が1つも残らない。完成させる操作は木を返し、途中の型は消える。
//!
//! 決定性。分割の軸は境界の最も長い軸、分ける位置は範囲のちょうど中央であり、並べ替えは中央の座標(同じ値なら
//! 三角形の番号)という全順序で行う。乱数も、実行のたびに変わる値も使わない。したがって同じ入力から必ず同じ木が
//! 組み上がる(`_doc/設計/世界の形と衝突基盤.md`「判断14: 決定性の維持」)。

use crate::shape::局所座標の軸平行の直方体;

use super::error::三角形網の生成エラー;
use super::hierarchy::三角形網の境界の木;
use super::node::{境界の木の節点, 境界の木の節点の位置, 節点の中身, 葉が持つ三角形の範囲};
use super::number::三角形網の三角形の番号;

// 葉が持てる三角形の数。これ以下になった範囲は分けずに葉にする。4に置くのは、葉の詳細判定4件と節点の境界の
// 比較1件が同じ桁の費用であり、これより小さくすると節点だけが増えるためである。
pub(super) const 葉に入れる三角形の上限: usize = 4;

// 組み立てが許す深さ。根を0と数える。走査のスタックの上限64から1を引いた値であり、深さがこの上限に収まる限り
// 走査は必ずスタックに収まる。
// 参照: `crates/blitz_collision/src/triangle_mesh/traversal_stack.rs`
const 階層の深さの上限: usize = 63;

pub(super) struct 三角形網の階層の構築 {
    三角形ごとの境界: Vec<局所座標の軸平行の直方体>,
    並べ替え: Vec<三角形網の三角形の番号>,
    節点: Vec<境界の木の節点>,
}

impl 三角形網の階層の構築 {
    pub(super) fn 三角形ごとの境界から始める(三角形ごとの境界: Vec<局所座標の軸平行の直方体>) -> Self {
        let 並べ替え = (0..三角形ごとの境界.len()).map(三角形網の三角形の番号::生成する).collect();
        Self {
            三角形ごとの境界,
            並べ替え,
            節点: Vec::new(),
        }
    }

    pub(super) fn 木を組み上げる(mut self) -> Result<三角形網の境界の木, 三角形網の生成エラー> {
        let 全体 = 葉が持つ三角形の範囲::二つの位置から生成する(0, self.並べ替え.len());
        let 根の位置 = self.範囲から節点を組む(全体, 0)?;
        Ok(三角形網の境界の木::検査済みの部品から組む(
            self.節点,
            self.並べ替え,
            根の位置,
        ))
    }

    pub(super) fn 三角形の境界を読む(&self, 三角形の番号: 三角形網の三角形の番号) -> 局所座標の軸平行の直方体 {
        self.三角形ごとの境界[三角形の番号.列の中の位置()]
    }

    // 三角形ごとの境界の列と、三角形の番号の並べ替えの列を、別々の借りとして取り出す。分割の規則が、境界を
    // 読みながら並べ替えを書き換えるために通る口である。2つを1つの借りで渡すと、読みと書き換えが同時に立たない。
    pub(super) fn 三角形ごとの境界と並べ替えを別々に借りる(
        &mut self,
    ) -> (&[局所座標の軸平行の直方体], &mut [三角形網の三角形の番号]) {
        (&self.三角形ごとの境界, &mut self.並べ替え)
    }

    // 範囲を1つの節点にする。上限より多い三角形を持つ範囲は2つに分け、子を先に組んでから自分を足す。
    fn 範囲から節点を組む(
        &mut self,
        範囲: 葉が持つ三角形の範囲,
        深さ: usize,
    ) -> Result<境界の木の節点の位置, 三角形網の生成エラー> {
        if 深さ >= 階層の深さの上限 {
            return Err(三角形網の生成エラー::階層の深さが上限を越えている);
        }
        let Some(境界) = self.範囲を包む箱を求める(範囲) else {
            return Err(三角形網の生成エラー::三角形が1件も無い);
        };
        if 範囲.件数() <= 葉に入れる三角形の上限 {
            return Ok(self.節点を1つ足す(境界, 節点の中身::葉 { 三角形の範囲: 範囲 }));
        }
        let 分ける位置 = self.範囲を分ける位置を求める(範囲, 境界);
        let 左の子 = self.範囲から節点を組む(
            葉が持つ三角形の範囲::二つの位置から生成する(範囲.位置の範囲().start, 分ける位置),
            深さ + 1,
        )?;
        let 右の子 = self.範囲から節点を組む(葉が持つ三角形の範囲::二つの位置から生成する(分ける位置, 範囲.位置の範囲().end), 深さ + 1)?;
        Ok(self.節点を1つ足す(境界, 節点の中身::内部 { 左の子, 右の子 }))
    }

    // 範囲の三角形をすべて包む箱。最小と最大を選ぶだけで丸めを1つも通さないため、包みは厳密である。
    fn 範囲を包む箱を求める(&self, 範囲: 葉が持つ三角形の範囲) -> Option<局所座標の軸平行の直方体> {
        範囲
            .位置の範囲()
            .map(|位置| self.三角形の境界を読む(self.並べ替え[位置]))
            .reduce(|畳んだ箱, 箱| 畳んだ箱.相手を含む箱を求める(&箱))
    }

    fn 節点を1つ足す(&mut self, 境界: 局所座標の軸平行の直方体, 中身: 節点の中身) -> 境界の木の節点の位置 {
        self.節点.push(境界の木の節点::生成する(境界, 中身));
        境界の木の節点の位置::生成する(self.節点.len() - 1)
    }
}
