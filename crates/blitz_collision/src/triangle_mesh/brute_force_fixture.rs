//! 階層を使わない総当たりの問い合わせ。反証だけが使う。
//!
//! 階層ありの答えが正しいことは、階層自身の不変条件を見ても言えない。境界が配下を包んでいても、走査が交わる
//! 節点を落としていれば答えは変わるからである。落としていないことを言うには、階層を通さずに全部の三角形を
//! 調べた答えと突き合わせるしかない。それがここに在る理由である。
//!
//! 詳細判定と最小の選び方は階層ありの問い合わせと同じ部品を使い、違うのは候補の挙げ方だけにする。三角形の番号の
//! 小さい順に全部を数えるため、階層の走査の順とは並びが違う。時刻が完全に並んだ入力では、残る三角形が2つの
//! 答えで食い違いうる。反証はその並びを作らない入力を選ぶ。

use crate::solver::最も小さい量の候補だけを覚える器;
use crate::triangle::{
    カプセルが三角形に最初に触れる点, 三角形のカプセルの掃引の問い合わせ, 三角形の線分の問い合わせ, 線分が三角形に最初に当たる点
};

use crate::shape::{形を掃引するカプセル, 形を貫く線分};

use super::error::三角形網の問い合わせエラー;
use super::mesh::三角形網;
use super::mesh_contact::{カプセルが三角形網に最初に触れる点, 掃引したカプセルの三角形網への接触};
use super::mesh_hit::{三角形網への最初の当たり, 線分が三角形網に最初に当たる点};
use super::number::三角形網の三角形の番号;

pub(super) fn 総当たりで線分の当たりを求める(
    網: &三角形網,
    線分: &形を貫く線分,
) -> Result<線分が三角形網に最初に当たる点, 三角形網の問い合わせエラー> {
    let mut 最小 = 最も小さい量の候補だけを覚える器::まだ何も無い状態から始める();
    for 三角形の番号 in 網の全部の三角形の番号を並べる(網) {
        let 問い合わせ = 三角形の線分の問い合わせ::三角形から生成する(網.三角形の幾何を読む(三角形の番号))?;
        if let 線分が三角形に最初に当たる点::三角形に当たる(当たり) = 問い合わせ.線分が三角形に最初に当たる点を求める(線分)?
        {
            最小.候補を1つ数える(当たり.交差時刻().値(), 三角形網への最初の当たり::生成する(三角形の番号, 当たり));
        }
    }
    Ok(match 最小.覚えている候補を取り出す() {
        Some(当たり) => 線分が三角形網に最初に当たる点::三角形網に当たる(当たり),
        None => 線分が三角形網に最初に当たる点::三角形網に当たらない,
    })
}

pub(super) fn 総当たりで掃引の接触を求める(
    網: &三角形網,
    カプセル: &形を掃引するカプセル,
) -> Result<カプセルが三角形網に最初に触れる点, 三角形網の問い合わせエラー> {
    let mut 最小 = 最も小さい量の候補だけを覚える器::まだ何も無い状態から始める();
    for 三角形の番号 in 網の全部の三角形の番号を並べる(網) {
        let 問い合わせ = 三角形のカプセルの掃引の問い合わせ::三角形から生成する(網.三角形の幾何を読む(三角形の番号))?;
        if let カプセルが三角形に最初に触れる点::三角形に触れる(接触) =
            問い合わせ.カプセルが三角形に最初に触れる点を求める(カプセル)?
        {
            最小.候補を1つ数える(接触.動けた割合().値(), 掃引したカプセルの三角形網への接触::生成する(三角形の番号, 接触));
        }
    }
    Ok(match 最小.覚えている候補を取り出す() {
        Some(接触) => カプセルが三角形網に最初に触れる点::三角形網に触れる(接触),
        None => カプセルが三角形網に最初に触れる点::三角形網に触れない,
    })
}

fn 網の全部の三角形の番号を並べる(網: &三角形網) -> impl Iterator<Item = 三角形網の三角形の番号> {
    (0..網.三角形の件数()).map(三角形網の三角形の番号::生成する)
}
