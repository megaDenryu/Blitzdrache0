//! 三角形網への線分の問い合わせ。受け取るのは線分、返すのは最も早く当たった三角形とその当たりである。
//!
//! 網そのもの(`crates/blitz_collision/src/triangle_mesh/mesh.rs`)と別のファイルへ置くのは、こちらが実行中の
//! 問い合わせという別の局面だからである。網の生成と保持は焼き込みの側にも現れるが、この問い合わせは実行中に
//! しか現れない。
//!
//! 手順は2段である。線分の両端に外接する箱を覆いにして階層を辿り、覆いに触れる葉の三角形だけを候補に挙げる。
//! 候補1枚ごとに三角形の線分の問い合わせを組んで詳細判定を行い、交差時刻の最も小さい当たりを選ぶ。
//!
//! 時刻が並んだときは、走査が先に渡した三角形の当たりを残す。走査の順は入力だけで決まるため、この選択も
//! 入力だけで決まる。隣り合う三角形が共有する辺の上に当たった場合は、どちらの三角形を返しても位置は同じ点で
//! あり、法線だけがその三角形の面の向きになる。
//!
//! 当たりを1つ見つけるたびに、始点からその当たりの点までを包む覆いへ走査を縮める。縮めが取り逃しも答えの
//! 違いも作らない根拠は`crates/blitz_collision/src/triangle_mesh/covering_scan.rs`にある。

use crate::shape::{局所座標の軸平行の直方体, 形を貫く線分};
use crate::solver::最も小さい量の候補だけを覚える器;
use crate::triangle::{三角形の線分の問い合わせ, 線分が三角形に最初に当たる点};

use super::covering_scan::覆いに触れる三角形の走査;
use super::error::三角形網の問い合わせエラー;
use super::mesh::三角形網;
use super::mesh_hit::{三角形網への最初の当たり, 線分が三角形網に最初に当たる点};

impl 三角形網 {
    /// 線分が網の三角形に最初に当たる点を求める。当たりが無い場合と、最も早い当たりを持つ場合を返す。
    pub fn 線分が三角形網に最初に当たる点を求める(
        &self,
        線分: &形を貫く線分,
    ) -> Result<線分が三角形網に最初に当たる点, 三角形網の問い合わせエラー> {
        let 覆い = 局所座標の軸平行の直方体::二点に外接する箱を求める(線分.始点(), 線分.終点());
        let mut 走査 = 覆いに触れる三角形の走査::根から始める(self.境界の木(), 覆い);
        let mut 最小 = 最も小さい量の候補だけを覚える器::まだ何も無い状態から始める();
        while let Some(三角形の番号) = 走査.次の三角形の番号を取り出す()? {
            let 問い合わせ = 三角形の線分の問い合わせ::面の向きを備えた三角形から生成する(
                self.面の向きを備えた三角形を読む(三角形の番号),
            );
            if let 線分が三角形に最初に当たる点::三角形に当たる(当たり) = 問い合わせ.線分が三角形に最初に当たる点を求める(線分)?
            {
                最小.候補を1つ数える(当たり.交差時刻().値(), 三角形網への最初の当たり::生成する(三角形の番号, 当たり));
                if let Some(最も早い当たり) = 最小.覚えている候補を見る() {
                    走査.覆いを縮める(
                        局所座標の軸平行の直方体::線分の当たりの点までを包む覆いを求める(
                            線分.始点(),
                            最も早い当たり.三角形への当たり().交差位置(),
                            線分.終点(),
                        ),
                    );
                }
            }
        }
        Ok(match 最小.覚えている候補を取り出す() {
            Some(当たり) => 線分が三角形網に最初に当たる点::三角形網に当たる(当たり),
            None => 線分が三角形網に最初に当たる点::三角形網に当たらない,
        })
    }
}
