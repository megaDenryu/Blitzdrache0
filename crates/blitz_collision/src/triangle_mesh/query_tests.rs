//! 三角形網への問い合わせが返す答えそのものの反証。手計算の当たりを返すこと・網から離れた線分が当たらない
//! こと・同じ入力を2度問い合わせると同じ答えが返ることを見る。
//!
//! 階層ありの答えが総当たりの答えと一致することは`brute_force_agreement_tests.rs`が別に見る。あちらは階層の
//! 走査が節点を落としていないことの反証であり、こちらは1つの問い合わせが返す値そのものの反証である。
//!
//! 手計算の当たりは、2かける2の格子の面の升目(0,0)の手前側の三角形で書く。その3頂点は(0,0,0)・(1,0,0)・
//! (1,1,1)であり、面に垂直な変位は(0,-1,1)であるから、平面は天頂の高さが南の座標に等しい面である。東0.7・
//! 南0.3の柱の上を落ちる線分は、高さ0.3でこの面に当たる。

use super::mesh_fixture::二かける二の格子の面の網;
use super::mesh_hit::線分が三角形網に最初に当たる点;
use super::number::三角形網の三角形の番号;
use super::query_fixture::{掃引の接触を求める, 線分の当たりを求める, 線分の組};

#[test]
fn 面を貫く線分は手計算の位置と三角形を返す() {
    let 当たり = match 線分の当たりを求める(&二かける二の格子の面の網(), [0.7, 10.0, 0.3], [0.7, -10.0, 0.3]) {
        線分が三角形網に最初に当たる点::三角形網に当たる(当たり) => 当たり,
        線分が三角形網に最初に当たる点::三角形網に当たらない => panic!("当たるはずの線分が当たらなかった"),
    };
    assert_eq!(当たり.三角形の番号(), 三角形網の三角形の番号::生成する(0));
    assert_eq!(当たり.三角形への当たり().交差時刻().値(), (10.0 - 0.3) / 20.0);
    let 位置 = 当たり.三角形への当たり().交差位置();
    // 天頂の成分に幅を置くのは、交差の位置を「始点 + 変位かける時刻」で組み直すためである。時刻が2進で
    // 割り切れないこの入力では、組み直した高さが期待値の10のマイナス15乗ほど上に出る。
    assert_eq!([位置.xのメートル(), 位置.zのメートル()], [0.7, 0.3]);
    assert!((位置.yのメートル() - 0.3).abs() <= 1.0e-12, "当たりの高さが期待から離れている");
}

#[test]
fn 網から離れた線分は当たらない() {
    assert_eq!(
        線分の当たりを求める(&二かける二の格子の面の網(), [5.0, 10.0, 5.0], [5.0, -10.0, 5.0]),
        線分が三角形網に最初に当たる点::三角形網に当たらない
    );
}

#[test]
fn 同じ入力を二度問い合わせると同じ答えが返る() {
    let 網 = 二かける二の格子の面の網();
    for (始点, 終点) in 線分の組 {
        assert_eq!(線分の当たりを求める(&網, 始点, 終点), 線分の当たりを求める(&網, 始点, 終点));
    }
    assert_eq!(
        掃引の接触を求める(&網, [0.7, 5.0, 0.3], 0.25, [0.0, -10.0, 0.0]),
        掃引の接触を求める(&網, [0.7, 5.0, 0.3], 0.25, [0.0, -10.0, 0.0])
    );
}
