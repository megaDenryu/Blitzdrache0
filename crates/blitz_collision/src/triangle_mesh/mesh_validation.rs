//! 三角形網の入力を検査しながら、三角形1枚ごとの幾何を組む工程。受け取るのは頂点の列と三角形の列、返すのは
//! 頂点の位置で表した三角形の列である。
//!
//! 検査と幾何の組み立てを1つの走査で行うのは、どちらも同じ「番号から頂点を引く」操作を通るためである。別々に
//! 走査すると、引き方が2つに分かれ、片方だけを直した食い違いが作れる。
//!
//! 面積が零の三角形を型付きエラーで拒む理由。面積が零だと面の平面も向きも定まらず、線分の当たりが返す単位法線を
//! 作れない。黙って落とすと、網が持つ三角形の番号と焼いた側が知っている番号がずれる。黙って通すと、詳細判定が
//! 三角形1枚ごとに失敗を返し、その失敗が問い合わせの失敗として上まで上がる。どちらも入口で拒むより悪い。
//! 焼く側は面積が零の三角形を取り除いてから渡す。それは網に載せる値ではなく、元のデータの壊れである。

use crate::shape::{三角形の頂点の番号, 局所座標の三角形, 形の局所座標の位置};

use super::error::三角形網の生成エラー;
use super::mesh_triangle::頂点の番号で表した三角形;
use super::number::三角形網の三角形の番号;

pub(super) fn 三角形ごとの幾何を組みながら検査する(
    頂点の位置: &[形の局所座標の位置],
    三角形: &[頂点の番号で表した三角形],
) -> Result<Vec<局所座標の三角形>, 三角形網の生成エラー> {
    if 三角形.is_empty() {
        return Err(三角形網の生成エラー::三角形が1件も無い);
    }
    三角形
        .iter()
        .enumerate()
        .map(|(列の中の位置, 一枚)| 三角形1枚の幾何を組む(頂点の位置, 三角形網の三角形の番号::生成する(列の中の位置), 一枚))
        .collect()
}

// 三角形1枚の幾何。3つの頂点の番号が列の中を指すことと、面積が零でないことをここで確かめる。
fn 三角形1枚の幾何を組む(
    頂点の位置: &[形の局所座標の位置],
    三角形の番号: 三角形網の三角形の番号,
    一枚: &頂点の番号で表した三角形,
) -> Result<局所座標の三角形, 三角形網の生成エラー> {
    let [第1, 第2, 第3] = 三角形の頂点の番号::並べる().map(|中の番号| {
        let 頂点の番号 = 一枚.頂点の番号(中の番号);
        頂点の位置.get(頂点の番号.列の中の位置()).copied().ok_or(
            三角形網の生成エラー::頂点の番号が頂点の列の外を指している {
                三角形の番号, 頂点の番号
            },
        )
    });
    let 幾何 = 局所座標の三角形::三つの頂点から生成する([第1?, 第2?, 第3?]);
    if 幾何.面積が零か() {
        return Err(三角形網の生成エラー::三角形の面積が零 { 三角形の番号 });
    }
    Ok(幾何)
}
