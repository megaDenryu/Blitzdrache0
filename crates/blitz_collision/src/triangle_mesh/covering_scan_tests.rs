//! 覆いに触れる三角形の走査の反証。覆いを縮めると、まだ積んだままの節点が捨てられて以後に渡す三角形が減ることを
//! 見る。縮めが効かなければ走査は網の全部の三角形を渡し続けるため、この反証が落ちる。
//!
//! 縮めた先を網から離れた箱に取るのは、どの節点が先に取り出されるかに答えを預けないためである。網に触れない箱へ
//! 縮めれば、スタックに残った節点はすべて捨てられ、渡し終える枚数は既に開いた葉の分だけになる。開いた葉の中の
//! 三角形は縮めた覆いで数え直さないため、残りは0にはならない。
//!
//! 縮めが答えを変えないことは`query_tests.rs`の総当たりとの一致が見る。総当たりの側は覆いを持たず、網の全部の
//! 三角形を数えるためである。

use crate::shape::局所座標の軸平行の直方体;

use super::covering_scan::覆いに触れる三角形の走査;
use super::hierarchy::三角形網の境界の木;
use super::mesh_fixture::{二かける二の格子の面の網, 局所の点};

fn 箱を作る(端: [f64; 3], もう一方の端: [f64; 3]) -> 局所座標の軸平行の直方体 {
    局所座標の軸平行の直方体::二点に外接する箱を求める(局所の点(端), 局所の点(もう一方の端))
}

fn 次の三角形が在るか(走査: &mut 覆いに触れる三角形の走査<'_>) -> bool {
    match 走査.次の三角形の番号を取り出す() {
        Ok(答え) => 答え.is_some(),
        Err(誤り) => panic!("試験用の走査が失敗した: {誤り}"),
    }
}

// 走査が渡し終えるまでの三角形の枚数。1枚渡した時点で縮めた覆いを渡す指定があれば、そこで渡す。
fn 渡し終えるまでの三角形の枚数を数える(
    木: &三角形網の境界の木,
    最初の覆い: 局所座標の軸平行の直方体,
    一枚目の後に縮める覆い: Option<局所座標の軸平行の直方体>,
) -> usize {
    let mut 走査 = 覆いに触れる三角形の走査::根から始める(木, 最初の覆い);
    let mut 枚数 = 0usize;
    while 次の三角形が在るか(&mut 走査) {
        枚数 += 1;
        if let (1, Some(覆い)) = (枚数, 一枚目の後に縮める覆い) {
            走査.覆いを縮める(覆い);
        }
    }
    枚数
}

#[test]
fn 網の全体を包む覆いは全部の三角形を渡す() {
    let 網 = 二かける二の格子の面の網();
    let 枚数 = 渡し終えるまでの三角形の枚数を数える(網.境界の木(), 箱を作る([-1.0, -1.0, -1.0], [3.0, 5.0, 3.0]), None);
    assert_eq!(枚数, 網.三角形の件数());
}

#[test]
fn 覆いを縮めると以後に渡す三角形が減る() {
    let 網 = 二かける二の格子の面の網();
    let 全体の覆い = 箱を作る([-1.0, -1.0, -1.0], [3.0, 5.0, 3.0]);
    let 縮めない枚数 = 渡し終えるまでの三角形の枚数を数える(網.境界の木(), 全体の覆い, None);
    let 縮めた枚数 =
        渡し終えるまでの三角形の枚数を数える(網.境界の木(), 全体の覆い, Some(箱を作る([10.0, 10.0, 10.0], [10.5, 10.5, 10.5])));
    assert!(
        縮めた枚数 < 縮めない枚数,
        "覆いを縮めても渡す三角形が減っていない(縮めない{縮めない枚数}枚、縮めた{縮めた枚数}枚)"
    );
}
