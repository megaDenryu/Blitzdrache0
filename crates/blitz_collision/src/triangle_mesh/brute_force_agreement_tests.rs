//! 階層ありの答えが総当たりの答えと一致することの反証。線分の問い合わせと掃引の問い合わせのそれぞれについて、
//! 見本の2つの網で見る。
//!
//! これが階層の正しさの反証である。階層が交わる節点を落としていれば、落とした先に在る三角形の当たりが
//! 総当たりの側にだけ出て、この反証が落ちる。当たりのところまで覆いを縮める工程も同じ形で見張られる。
//! 総当たりの側は覆いを持たず、網の全部の三角形を数えるためである。
//!
//! 見本を2つ置くのは階層の形が違うためである。四面体は4枚であるから葉1つに収まり、根がそのまま葉になる。
//! 2かける2の格子の面は8枚であるから2段に分かれ、内部節点と葉の両方が現れる。
//!
//! 線分の側は、格子の面を座標軸に平行でない向きへ回した網でも一致を見る。当たりの位置は共有辺の水密性のため
//! 三角形の頂点の重心座標で組んでおり、覆いを縮める終端の演算列(線分の式)と別の演算列である。回さない網では
//! 2つの点が同じ値になりやすく、どちらの演算列で終端を組んでも同じ覆いになるため、縮めの前提が見張られない。
//! 2つの点が現に食い違うことは`回した網の当たりでは重心座標の位置と線分の式の点が食い違う`が別に確かめる。
//! 参照: `crates/blitz_collision/src/shape/local_box_cover.rs`

use super::mesh::三角形網;
use super::mesh_fixture::{
    二かける二の格子の面の網, 四面体の網, 回した二かける二の格子の面の網, 座標軸に平行でない向きへ回した点, 線分を作る
};
use super::mesh_hit::線分が三角形網に最初に当たる点;
use super::query_fixture::{
    掃引の接触を求める, 掃引の組, 総当たりの掃引の接触を求める, 総当たりの線分の当たりを求める, 線分の当たりを求める, 線分の組,
};

#[test]
fn 階層ありの線分の答えは総当たりと一致する() {
    for 網 in [二かける二の格子の面の網(), 四面体の網()] {
        for (始点, 終点) in 線分の組 {
            assert_eq!(線分の当たりを求める(&網, 始点, 終点), 総当たりの線分の当たりを求める(&網, 始点, 終点));
        }
    }
}

#[test]
fn 回した網でも階層ありの線分の答えは総当たりと一致する() {
    let 網 = 回した二かける二の格子の面の網();
    for (始点, 終点) in 回した線分の組() {
        assert_eq!(線分の当たりを求める(&網, 始点, 終点), 総当たりの線分の当たりを求める(&網, 始点, 終点));
    }
}

#[test]
fn 回した網の当たりでは重心座標の位置と線分の式の点が食い違う() {
    let 網 = 回した二かける二の格子の面の網();
    let 食い違った組の数 = 二つの演算列の点が食い違う組を数える(&網);
    assert!(
        食い違った組の数 > 0,
        "回した網のどの線分でも重心座標の当たりの位置と線分の式の点が一致した。この組では覆いの終端をどちらの演算列で組んでも同じ覆いになるため、一致の反証が縮めの演算列を見張らない"
    );
}

// 見本の線分の組を、網と同じ向きへ回したもの。網だけを回すと線分が網を外れて当たりが1つも出ない。
fn 回した線分の組() -> [([f64; 3], [f64; 3]); 7] {
    線分の組.map(|(始点, 終点)| (座標軸に平行でない向きへ回した点(始点), 座標軸に平行でない向きへ回した点(終点)))
}

// 当たりの位置を三角形の頂点の重心座標で組んだ値と、交差時刻から線分の式で組んだ値が食い違う線分の数。
fn 二つの演算列の点が食い違う組を数える(網: &三角形網) -> usize {
    let mut 数 = 0usize;
    for (始点, 終点) in 回した線分の組() {
        let 線分 = 線分を作る(始点, 終点);
        let 線分が三角形網に最初に当たる点::三角形網に当たる(当たり) = 線分の当たりを求める(網, 始点, 終点)
        else {
            continue;
        };
        let 線分の式の点 = match 線分.線分上の点を求める(当たり.三角形への当たり().交差時刻()) {
            Ok(点) => 点,
            Err(誤り) => panic!("交差時刻から線分の式で点を組めなかった: {誤り}"),
        };
        if 線分の式の点 != 当たり.三角形への当たり().交差位置() {
            数 += 1;
        }
    }
    数
}

#[test]
fn 階層ありの掃引の答えは総当たりと一致する() {
    for 網 in [二かける二の格子の面の網(), 四面体の網()] {
        for (中心, 変位) in 掃引の組 {
            assert_eq!(
                掃引の接触を求める(&網, 中心, 0.25, 変位),
                総当たりの掃引の接触を求める(&網, 中心, 0.25, 変位)
            );
        }
    }
}
