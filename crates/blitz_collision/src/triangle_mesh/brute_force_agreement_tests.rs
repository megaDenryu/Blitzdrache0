//! 階層ありの答えが総当たりの答えと一致することの反証。線分の問い合わせと掃引の問い合わせのそれぞれについて、
//! 見本の2つの網で見る。
//!
//! これが階層の正しさの反証である。階層が交わる節点を落としていれば、落とした先に在る三角形の当たりが
//! 総当たりの側にだけ出て、この反証が落ちる。当たりのところまで覆いを縮める工程も同じ形で見張られる。
//! 総当たりの側は覆いを持たず、網の全部の三角形を数えるためである。
//!
//! 見本を2つ置くのは階層の形が違うためである。四面体は4枚であるから葉1つに収まり、根がそのまま葉になる。
//! 2かける2の格子の面は8枚であるから2段に分かれ、内部節点と葉の両方が現れる。

use super::mesh_fixture::{二かける二の格子の面の網, 四面体の網};
use super::query_fixture::{
    掃引の接触を求める, 掃引の組, 総当たりの掃引の接触を求める, 総当たりの線分の当たりを求める, 線分の当たりを求める, 線分の組,
};

#[test]
fn 階層ありの線分の答えは総当たりと一致する() {
    for 網 in [二かける二の格子の面の網(), 四面体の網()] {
        for (始点, 終点) in 線分の組 {
            assert_eq!(線分の当たりを求める(&網, 始点, 終点), 総当たりの線分の当たりを求める(&網, 始点, 終点));
        }
    }
}

#[test]
fn 階層ありの掃引の答えは総当たりと一致する() {
    for 網 in [二かける二の格子の面の網(), 四面体の網()] {
        for (中心, 変位) in 掃引の組 {
            assert_eq!(
                掃引の接触を求める(&網, 中心, 0.25, 変位),
                総当たりの掃引の接触を求める(&網, 中心, 0.25, 変位)
            );
        }
    }
}
