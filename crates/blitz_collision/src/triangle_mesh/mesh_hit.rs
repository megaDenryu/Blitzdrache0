//! 線分が三角形網に最初に当たった点と、当たらなかったことを表す枝。
//!
//! 三角形1枚への当たりをそのまま持ち、三角形の番号を添えるだけにするのは、網が返す幾何学的な事実が1枚への
//! 当たりと同じものだからである。時刻も位置も法線も特徴も、当たった1枚が答えたものである。番号を添えるのは、
//! 呼び出し側が同じ面へ触れ続けているかを追えるようにするためである。

use crate::triangle::三角形への最初の当たり;

use super::number::三角形網の三角形の番号;

/// 線分が三角形網に最初に当たった点。終点まで当たらなかった枝と、当たりを持つ枝の2つである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 線分が三角形網に最初に当たる点 {
    /// 終点まで網のどの三角形にも当たらなかった。
    三角形網に当たらない,
    /// 網のどれかの三角形に当たり、そのうち最も早い当たりを持つ。
    三角形網に当たる(三角形網への最初の当たり),
}

/// 線分が三角形網に最初に当たった1つの事実。当たった三角形の番号と、その三角形への当たりを持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 三角形網への最初の当たり {
    三角形の番号: 三角形網の三角形の番号,
    三角形への当たり: 三角形への最初の当たり,
}

impl 三角形網への最初の当たり {
    pub(super) fn 生成する(
        三角形の番号: 三角形網の三角形の番号, 三角形への当たり: 三角形への最初の当たり
    ) -> Self {
        Self {
            三角形の番号,
            三角形への当たり,
        }
    }

    /// 当たった三角形の、網の三角形の列の中での番号。
    pub fn 三角形の番号(&self) -> 三角形網の三角形の番号 {
        self.三角形の番号
    }

    /// 当たった三角形1枚への当たり。交差時刻・交差位置・接触面の単位法線・当たった特徴を持つ。
    pub fn 三角形への当たり(&self) -> 三角形への最初の当たり {
        self.三角形への当たり
    }
}
