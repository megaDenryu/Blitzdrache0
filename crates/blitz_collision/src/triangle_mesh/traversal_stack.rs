//! 階層を辿る走査が積む節点の位置のスタック。固定の長さの配列で持ち、確保を1度も起こさない。
//!
//! 上限を64に置く根拠。組み立ての分割は、範囲を並べ替えてからちょうど中央で切るため、どちらの側も必ず1件以上に
//! なる。したがって深さが1段下がるごとに件数は半分以下になり、木の深さは三角形の件数の2を底とする対数以下で
//! ある。件数はメモリに載った列の長さであるから2の64乗を越えられず、深さは64を越えない。深さ63の木を作るには
//! 2の63乗枚の三角形が要り、1枚あたり最小でも数十バイトであるから実在しない。
//!
//! スタックが同時に持つ節点の数は、深さに1を足した数に収まる。節点を1つ取り出して2つの子を積む操作は、
//! 段ごとに「まだ辿っていない兄弟」を高々1つ残すためである。したがって上限64は、実在しうるどの木よりも深い
//! 木まで辿れる。それでも超過を型付きエラーで返すのは、階層が壊れている場合に黙って候補を落とさないためである。

use super::error::三角形網の問い合わせエラー;
use super::node::境界の木の節点の位置;

// 同時に積める節点の位置の数。
const 走査のスタックの上限: usize = 64;

pub(super) struct 木の走査のスタック {
    積んだ位置: [境界の木の節点の位置; 走査のスタックの上限],
    積んだ数: usize,
}

impl 木の走査のスタック {
    pub(super) fn 根だけを積んだ状態から始める(根の位置: 境界の木の節点の位置) -> Self {
        Self {
            積んだ位置: [根の位置; 走査のスタックの上限],
            積んだ数: 1,
        }
    }

    pub(super) fn 積む(&mut self, 位置: 境界の木の節点の位置) -> Result<(), 三角形網の問い合わせエラー> {
        let Some(積む先) = self.積んだ位置.get_mut(self.積んだ数) else {
            return Err(三角形網の問い合わせエラー::走査のスタックが上限を越えている);
        };
        *積む先 = 位置;
        self.積んだ数 += 1;
        Ok(())
    }

    pub(super) fn 取り出す(&mut self) -> Option<境界の木の節点の位置> {
        let 取り出す位置 = self.積んだ数.checked_sub(1)?;
        self.積んだ数 = 取り出す位置;
        self.積んだ位置.get(取り出す位置).copied()
    }
}
