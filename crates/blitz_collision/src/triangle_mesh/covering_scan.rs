//! 覆いに触れる三角形の走査: 覆いの箱1つを受け取り、それに境界が触れる葉の三角形を1つずつ渡すセッション型である。
//!
//! コールバックを渡す形にしないのは、走査の側が「次を1つ出す」以上のことを決めていないためである。何を渡された
//! ときに何をするかは問い合わせの側が決める。線分の問い合わせと掃引の問い合わせがこの1つの走査を共有し、
//! 階層の辿り方はここ1箇所になる。
//!
//! 辿り方は、根から始めて境界が覆いと交わる節点だけを下る深さ優先である。積むのは明示のスタックであり、
//! 確保は1度も起きない。走る順は、節点を取り出したときに左の子・右の子の順で積み、後に積んだ右の子から取り出す
//! 順である。この順は入力だけで決まるため、同じ網と同じ覆いなら三角形は必ず同じ順で出る。
//!
//! 当たりが1つ見つかったら、そこまで切り詰めた覆いを渡し直せる。渡された覆いはその後に取り出す節点の判定へ
//! そのまま効くため、まだ積んだままの節点も、これから下る枝も、縮めた覆いに触れなければ捨てられる。
//!
//! 縮めが取り逃しを作らない根拠。線分も掃引も、媒介変数について各成分が単調な動きであるから、当たりの
//! 媒介変数までの範囲は始まりの姿勢と当たりの姿勢の2つに外接する箱に収まる。当たりの媒介変数より手前で
//! 当たる三角形は、その範囲の中に接触の点を持ち、その点は三角形を包む箱の中に在る。したがってその三角形の
//! 箱は縮めた覆いと交わり、配下を包む親の節点の境界も交わる。切り詰めが端へ入れる丸めは、覆いを組む側が
//! `crates/blitz_collision/src/shape/cover_rounding_margin.rs`の幅で外向きへ包む。
//!
//! 答えが変わらない根拠。捨てられるのは、当たりの媒介変数より後ろでしか当たらない三角形だけである。それらは
//! 最小を選ぶ比較で残らないため、走査から外しても答えは同じである。媒介変数がちょうど並んだ三角形は縮めた
//! 覆いに触れたままであり、先に渡した候補を残す決まりも変わらない。

use crate::shape::局所座標の軸平行の直方体;

use super::error::三角形網の問い合わせエラー;
use super::hierarchy::三角形網の境界の木;
use super::node::{境界の木の節点の位置, 節点の中身};
use super::number::三角形網の三角形の番号;
use super::traversal_stack::木の走査のスタック;

pub(super) struct 覆いに触れる三角形の走査<'網> {
    木: &'網 三角形網の境界の木,
    覆い: 局所座標の軸平行の直方体,
    スタック: 木の走査のスタック,
    今の葉の残り: std::ops::Range<usize>,
}

impl<'網> 覆いに触れる三角形の走査<'網> {
    pub(super) fn 根から始める(木: &'網 三角形網の境界の木, 覆い: 局所座標の軸平行の直方体) -> Self {
        Self {
            木,
            覆い,
            スタック: 木の走査のスタック::根だけを積んだ状態から始める(木.根の位置()),
            今の葉の残り: 0..0,
        }
    }

    // 覆いを渡し直す。見つけた当たりのところまで切り詰めた覆いを受け取り、以後の節点の判定をそれで行う。
    //
    // 前提: 渡す覆いが、まだ答えになりうる範囲を包んでいること。包まない覆いを渡すと、答えになりうる三角形が
    // 候補から落ちる。
    pub(super) fn 覆いを縮める(&mut self, 縮めた覆い: 局所座標の軸平行の直方体) {
        self.覆い = 縮めた覆い;
    }

    // 次の候補の三角形。覆いに触れる葉をすべて出し切ったら値なしを返す。
    pub(super) fn 次の三角形の番号を取り出す(
        &mut self,
    ) -> Result<Option<三角形網の三角形の番号>, 三角形網の問い合わせエラー> {
        loop {
            if let Some(位置) = self.今の葉の残り.next() {
                return Ok(Some(self.木.並べ替えの位置が指す三角形(位置)));
            }
            let Some(節点の位置) = self.スタック.取り出す() else {
                return Ok(None);
            };
            self.節点を1つ調べる(節点の位置)?;
        }
    }

    // 節点1つを調べる。境界が覆いと交わらない節点は配下ごと捨て、交わる内部節点は子を積み、交わる葉は
    // その三角形の範囲を次に出す並びにする。
    fn 節点を1つ調べる(&mut self, 位置: 境界の木の節点の位置) -> Result<(), 三角形網の問い合わせエラー> {
        let 節点 = self.木.節点を読む(位置);
        if !節点.境界().相手と交わるか(&self.覆い) {
            return Ok(());
        }
        match 節点.中身() {
            節点の中身::内部 { 左の子, 右の子 } => {
                self.スタック.積む(左の子)?;
                self.スタック.積む(右の子)?;
            }
            節点の中身::葉 { 三角形の範囲 } => self.今の葉の残り = 三角形の範囲.位置の範囲(),
        }
        Ok(())
    }
}
