//! 掃引したカプセルが三角形網に最初に触れた点と、触れなかったことを表す枝。
//!
//! 三角形1枚への接触をそのまま持ち、三角形の番号を添えるだけにする理由は、線分の当たりと同じである。
//! 動けた割合も接触位置も法線も特徴も、触れた1枚が答えたものである。

use crate::triangle::掃引したカプセルの三角形への接触;

use super::number::三角形網の三角形の番号;

/// 掃引したカプセルが三角形網に最初に触れた点。変位の全体を動いても触れなかった枝と、接触を持つ枝の2つである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum カプセルが三角形網に最初に触れる点 {
    /// 変位の全体を動いても網のどの三角形にも触れなかった。
    三角形網に触れない,
    /// 網のどれかの三角形に触れ、そのうち最も早い接触を持つ。
    三角形網に触れる(掃引したカプセルの三角形網への接触),
}

/// 掃引したカプセルが三角形網へ触れた1つの事実。触れた三角形の番号と、その三角形への接触を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 掃引したカプセルの三角形網への接触 {
    三角形の番号: 三角形網の三角形の番号,
    三角形への接触: 掃引したカプセルの三角形への接触,
}

impl 掃引したカプセルの三角形網への接触 {
    pub(super) fn 生成する(
        三角形の番号: 三角形網の三角形の番号, 三角形への接触: 掃引したカプセルの三角形への接触
    ) -> Self {
        Self {
            三角形の番号,
            三角形への接触,
        }
    }

    /// 触れた三角形の、網の三角形の列の中での番号。
    pub fn 三角形の番号(&self) -> 三角形網の三角形の番号 {
        self.三角形の番号
    }

    /// 触れた三角形1枚への接触。動けた割合・接触位置・接触の単位法線・触れた特徴を持つ。
    pub fn 三角形への接触(&self) -> 掃引したカプセルの三角形への接触 {
        self.三角形への接触
    }
}
