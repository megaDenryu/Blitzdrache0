//! 三角形網の境界の木: ノードの列と三角形の番号の並べ替えを持ち、根から辿れる階層そのものである。
//!
//! ノードを1本の列で持ち、子を位置で指すのは、ノード1つにつき確保が起きるのを避けるためと、直列化する側が列を
//! そのまま書き出せるようにするためである(実行時形式は物理アセット変換が持つ)。
//!
//! 並べ替えは、組み立てが三角形の番号を葉ごとに固めた列である。葉はその連続した区間を持つ。三角形の列そのものを
//! 並べ替えないのは、答えが返す三角形の番号を、網を焼いた側が知っている番号のまま保つためである。
//!
//! 不変条件: ノードの境界は、そのノードの配下にあるすべての三角形を包む。境界は頂点の位置の最小と最大を選ぶだけで
//! 組むため丸めを1つも通さず、この包みは厳密である。ノードの位置と並べ替えの位置は、どちらも組み立てが作った
//! 列の中を指す。列の外を指す位置は組み立てが作らないため、読み取りは添字でそのまま引く。

use super::node::{境界の木のノード, 境界の木のノードの位置};
use super::number::三角形網の三角形の番号;

pub(super) struct 三角形網の境界の木 {
    ノード: Vec<境界の木のノード>,
    三角形の並べ替え: Vec<三角形網の三角形の番号>,
    根の位置: 境界の木のノードの位置,
}

impl 三角形網の境界の木 {
    // 組み立てが作った部品から組む。位置が列の中を指すことは組み立てが保証する。
    pub(super) fn 検査済みの部品から組む(ノード: Vec<境界の木のノード>, 三角形の並べ替え: Vec<三角形網の三角形の番号>, 根の位置: 境界の木のノードの位置) -> Self {
        Self {
            ノード, 三角形の並べ替え, 根の位置
        }
    }

    pub(super) fn 根の位置(&self) -> 境界の木のノードの位置 {
        self.根の位置
    }

    pub(super) fn ノードを読む(&self, 位置: 境界の木のノードの位置) -> 境界の木のノード {
        self.ノード[位置.列の中の位置()]
    }

    // 並べ替えの列の中の1つの位置が指す三角形の番号。葉が持つ範囲の中の位置を、走査がこの口で三角形へ直す。
    pub(super) fn 並べ替えの位置が指す三角形(&self, 位置: usize) -> 三角形網の三角形の番号 {
        self.三角形の並べ替え[位置]
    }
}
