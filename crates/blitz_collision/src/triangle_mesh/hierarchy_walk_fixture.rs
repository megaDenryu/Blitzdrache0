//! 階層を根から辿って中身を取り出す道具。反証だけが使う。
//!
//! 実行中の走査(`crates/blitz_collision/src/triangle_mesh/covering_scan.rs`)と別に置くのは、あちらが覆いと
//! 交わるノードだけを下るのに対し、こちらが全部のノードを下るためである。不変条件の反証は、覆いに関わらず木の
//! すべてを見なければ言えない。

use super::hierarchy::三角形網の境界の木;
use super::node::{ノードの中身, 境界の木のノード, 境界の木のノードの位置};
use super::number::三角形網の三角形の番号;

// ノードの配下に在る三角形の番号を、葉の並びの順に集める。
pub(super) fn 配下の三角形を並べる(木: &三角形網の境界の木, 位置: 境界の木のノードの位置) -> Vec<三角形網の三角形の番号> {
    match 木.ノードを読む(位置).中身() {
        ノードの中身::葉 { 三角形の範囲 } => 三角形の範囲.位置の範囲().map(|位置| 木.並べ替えの位置が指す三角形(位置)).collect(),
        ノードの中身::内部 { 左の子, 右の子 } => {
            let mut 集めた = 配下の三角形を並べる(木, 左の子);
            集めた.extend(配下の三角形を並べる(木, 右の子));
            集めた
        }
    }
}

// ノードそのものを、根から深さ優先の順に集める。2つの木を突き合わせるために使う。
pub(super) fn ノードを根から並べる(木: &三角形網の境界の木, 位置: 境界の木のノードの位置) -> Vec<境界の木のノード> {
    let ノード = 木.ノードを読む(位置);
    let mut 集めた = vec![ノード];
    if let ノードの中身::内部 { 左の子, 右の子 } = ノード.中身() {
        集めた.extend(ノードを根から並べる(木, 左の子));
        集めた.extend(ノードを根から並べる(木, 右の子));
    }
    集めた
}
