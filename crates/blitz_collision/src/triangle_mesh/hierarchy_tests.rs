//! 階層の不変条件の反証。節点の境界が配下の三角形をすべて包むこと・葉が全三角形をちょうど1回ずつ持つこと・
//! 葉の枚数が上限に収まること・上限に収まる網では根がそのまま葉になることを見る。
//!
//! 包みを幅なしの等号と不等号で見るのは、境界が頂点の位置の最小と最大を選ぶだけで組まれ、丸めを1つも通さない
//! ためである。幅を置くと、丸めが入る形へ変えてもこの反証が落ちなくなる。
//!
//! 同じ入力から2度組んだ木が一致することは`build_determinism_tests.rs`が別に見る。

use crate::shape::三角形の頂点の番号;

use super::hierarchy::三角形網の境界の木;
use super::hierarchy_builder::葉に入れる三角形の上限;
use super::hierarchy_walk_fixture::配下の三角形を並べる;
use super::mesh::三角形網;
use super::mesh_fixture::{二かける二の格子の面の網, 四面体の網};
use super::node::{境界の木の節点の位置, 節点の中身};
use super::number::三角形網の三角形の番号;

fn 節点が配下を包むことを確かめる(網: &三角形網, 位置: 境界の木の節点の位置) {
    let 木 = 網.境界の木();
    let 境界 = 木.節点を読む(位置).境界();
    let 最小 = 境界.最小の端();
    let 最大 = 境界.最大の端();
    for 番号 in 配下の三角形を並べる(木, 位置) {
        let 幾何 = 網.三角形の幾何を読む(番号);
        for 中の番号 in 三角形の頂点の番号::並べる() {
            let 頂点 = 幾何.頂点の位置(中の番号);
            assert!(
                最小.xのメートル() <= 頂点.xのメートル() && 頂点.xのメートル() <= 最大.xのメートル(),
                "東の成分が境界の外にある"
            );
            assert!(
                最小.yのメートル() <= 頂点.yのメートル() && 頂点.yのメートル() <= 最大.yのメートル(),
                "天頂の成分が境界の外にある"
            );
            assert!(
                最小.zのメートル() <= 頂点.zのメートル() && 頂点.zのメートル() <= 最大.zのメートル(),
                "南の成分が境界の外にある"
            );
        }
    }
    if let 節点の中身::内部 { 左の子, 右の子 } = 木.節点を読む(位置).中身() {
        節点が配下を包むことを確かめる(網, 左の子);
        節点が配下を包むことを確かめる(網, 右の子);
    }
}

fn 葉の枚数が上限に収まることを確かめる(木: &三角形網の境界の木, 位置: 境界の木の節点の位置) {
    match 木.節点を読む(位置).中身() {
        節点の中身::葉 { 三角形の範囲 } => {
            assert!(三角形の範囲.件数() <= 葉に入れる三角形の上限, "葉が持つ三角形が上限を越えている");
        }
        節点の中身::内部 { 左の子, 右の子 } => {
            葉の枚数が上限に収まることを確かめる(木, 左の子);
            葉の枚数が上限に収まることを確かめる(木, 右の子);
        }
    }
}

#[test]
fn どの節点の境界も配下の三角形の頂点をすべて包む() {
    let 網 = 二かける二の格子の面の網();
    節点が配下を包むことを確かめる(&網, 網.境界の木().根の位置());
}

#[test]
fn 葉は全部の三角形をちょうど一度ずつ持つ() {
    let 網 = 二かける二の格子の面の網();
    let mut 集めた = 配下の三角形を並べる(網.境界の木(), 網.境界の木().根の位置());
    集めた.sort_unstable();
    let 期待: Vec<三角形網の三角形の番号> = (0..網.三角形の件数()).map(三角形網の三角形の番号::生成する).collect();
    assert_eq!(集めた, 期待);
}

#[test]
fn 葉が持つ三角形は上限に収まる() {
    let 網 = 二かける二の格子の面の網();
    葉の枚数が上限に収まることを確かめる(網.境界の木(), 網.境界の木().根の位置());
}

#[test]
fn 上限に収まる枚数の網は根がそのまま葉になる() {
    let 網 = 四面体の網();
    let 木 = 網.境界の木();
    let 節点の中身::葉 { 三角形の範囲 } = 木.節点を読む(木.根の位置()).中身() else {
        panic!("4枚の網の根が葉になっていない");
    };
    assert_eq!(三角形の範囲.件数(), 4);
}
