//! 境界の木の節点と、その節点を指す位置、および葉が持つ三角形の範囲。3つを1つのファイルに置くのは、
//! どれも「木の中のどこを指すか」という1つの概念を成し、互いを見ずには意味が決まらないためである。
//!
//! 節点は自分の境界と中身を持つ。中身は、2つの子を指す内部節点か、三角形の範囲を持つ葉のどちらかである。
//! 判別共用体にするのは、内部節点だけが子を持ち葉だけが三角形を持つという排他を型で表すためである。
//!
//! 子と範囲を節点そのものではなく位置で持つのは、木を1本の配列に並べて保持するためである。節点が子を所有すると
//! 節点1つにつき確保が起き、木を辿るたびに離れた番地を追うことになる。
//!
//! 範囲が指すのは三角形の番号そのものではなく、木が持つ並べ替えの列の中の位置である。組み立てが三角形の番号を
//! 並べ替え、葉はその連続した区間を持つ。

use crate::shape::局所座標の軸平行の直方体;

// 木が保持する節点の列の中の位置。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 境界の木の節点の位置(usize);

impl 境界の木の節点の位置 {
    pub(super) fn 生成する(列の中の位置: usize) -> Self {
        Self(列の中の位置)
    }

    pub(super) fn 列の中の位置(&self) -> usize {
        self.0
    }
}

// 葉が持つ三角形の範囲。木が持つ並べ替えの列の中の、始まりの位置と終わりの位置(終わりは含まない)で表す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 葉が持つ三角形の範囲 {
    始まりの位置: usize,
    終わりの位置: usize,
}

impl 葉が持つ三角形の範囲 {
    pub(super) fn 二つの位置から生成する(始まりの位置: usize, 終わりの位置: usize) -> Self {
        Self {
            始まりの位置, 終わりの位置
        }
    }

    pub(super) fn 位置の範囲(&self) -> std::ops::Range<usize> {
        self.始まりの位置..self.終わりの位置
    }

    pub(super) fn 件数(&self) -> usize {
        self.終わりの位置.saturating_sub(self.始まりの位置)
    }
}

// 境界の木の節点1つ。配下の三角形をすべて包む境界と、内部節点か葉かの中身を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 境界の木の節点 {
    境界: 局所座標の軸平行の直方体,
    中身: 節点の中身,
}

impl 境界の木の節点 {
    pub(super) fn 生成する(境界: 局所座標の軸平行の直方体, 中身: 節点の中身) -> Self {
        Self { 境界, 中身 }
    }

    pub(super) fn 境界(&self) -> 局所座標の軸平行の直方体 {
        self.境界
    }

    pub(super) fn 中身(&self) -> 節点の中身 {
        self.中身
    }
}

// 節点の中身。2つの子を指す内部節点か、三角形の範囲を持つ葉のどちらかである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 節点の中身 {
    内部 {
        左の子: 境界の木の節点の位置,
        右の子: 境界の木の節点の位置,
    },
    葉 {
        三角形の範囲: 葉が持つ三角形の範囲,
    },
}
