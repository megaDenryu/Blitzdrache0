//! 三角形網への問い合わせの反証が共有する入口。階層ありの問い合わせと総当たりの問い合わせを、成分の並びで
//! 呼んで答えだけを返す4つの道具と、反証が共有する線分の組を持つ。
//!
//! 網と線分とカプセルを組む道具は`mesh_fixture.rs`、総当たりの問い合わせそのものは`brute_force_fixture.rs`が
//! 持つ。ここに在るのはその2つを呼び分けて失敗を試験の破綻へ変える薄い層であり、反証の本文が
//! `match`の枝で埋まらないためのものである。

use super::brute_force_fixture::{総当たりで掃引の接触を求める, 総当たりで線分の当たりを求める};
use super::mesh::三角形網;
use super::mesh_contact::カプセルが三角形網に最初に触れる点;
use super::mesh_fixture::{カプセルを作る, 線分を作る};
use super::mesh_hit::線分が三角形網に最初に当たる点;

pub(super) fn 線分の当たりを求める(
    網: &三角形網, 始点: [f64; 3], 終点: [f64; 3]
) -> 線分が三角形網に最初に当たる点 {
    match 網.線分が三角形網に最初に当たる点を求める(&線分を作る(始点, 終点)) {
        Ok(答え) => 答え,
        Err(誤り) => panic!("網への線分の問い合わせが失敗した: {誤り}"),
    }
}

pub(super) fn 総当たりの線分の当たりを求める(
    網: &三角形網,
    始点: [f64; 3],
    終点: [f64; 3],
) -> 線分が三角形網に最初に当たる点 {
    match 総当たりで線分の当たりを求める(網, &線分を作る(始点, 終点)) {
        Ok(答え) => 答え,
        Err(誤り) => panic!("総当たりの線分の問い合わせが失敗した: {誤り}"),
    }
}

pub(super) fn 掃引の接触を求める(
    網: &三角形網,
    中心: [f64; 3],
    半径: f64,
    変位: [f64; 3],
) -> カプセルが三角形網に最初に触れる点 {
    match 網.カプセルが三角形網に最初に触れる点を求める(&カプセルを作る(中心, 中心, 半径, 変位)) {
        Ok(答え) => 答え,
        Err(誤り) => panic!("網への掃引の問い合わせが失敗した: {誤り}"),
    }
}

pub(super) fn 総当たりの掃引の接触を求める(
    網: &三角形網,
    中心: [f64; 3],
    半径: f64,
    変位: [f64; 3],
) -> カプセルが三角形網に最初に触れる点 {
    match 総当たりで掃引の接触を求める(網, &カプセルを作る(中心, 中心, 半径, 変位)) {
        Ok(答え) => 答え,
        Err(誤り) => panic!("総当たりの掃引の問い合わせが失敗した: {誤り}"),
    }
}

