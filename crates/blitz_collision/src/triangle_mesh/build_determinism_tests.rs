//! 階層の組み立ての決定性の反証。同じ入力から2度組んだ木が、節点の境界と中身、および三角形の並べ替えまで
//! 一致することを見る。
//!
//! 幅を置かずに一致を見るのは、組み立てが分割の軸・分ける位置・並べ替えの順のどれも入力だけから決めており、
//! 2度の組み立てがまったく同じ演算列を通るためである。値が近いだけの一致では、乱数や実行のたびに変わる値が
//! 紛れ込んだことを見つけられない。

use super::hierarchy_walk_fixture::節点を根から並べる;
use super::mesh_fixture::二かける二の格子の面の網;

#[test]
fn 同じ入力から二度組んだ木は節点まで一致する() {
    let 一度目 = 二かける二の格子の面の網();
    let 二度目 = 二かける二の格子の面の網();
    assert_eq!(
        節点を根から並べる(一度目.境界の木(), 一度目.境界の木().根の位置()),
        節点を根から並べる(二度目.境界の木(), 二度目.境界の木().根の位置())
    );
    for 並べ替えの位置 in 0..一度目.三角形の件数() {
        assert_eq!(
            一度目.境界の木().並べ替えの位置が指す三角形(並べ替えの位置),
            二度目.境界の木().並べ替えの位置が指す三角形(並べ替えの位置)
        );
    }
}
