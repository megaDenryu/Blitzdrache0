//! 三角形網の中の頂点と三角形を指す2つの番号。どちらも網が保持する列の中の位置である。
//!
//! 裸の添字で指さないのは、頂点の番号と三角形の番号が取り違えても型が通る同じ整数だからである。網の三角形は
//! 頂点の番号を3つ持ち、問い合わせの答えは三角形の番号を持つ。この2つが同じ綴りで並ぶと、片方をもう片方の列へ
//! 渡す誤りが実行するまで出ない。
//!
//! 中身を`usize`にするのは、番号が指す先がメモリに載った列の位置そのものだからである。実行時形式へ焼くときの
//! 幅(32ビット等)は直列化の側が決めることであり、その形式は物理アセット変換が持つ。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断11: 静的衝突メッシュは階層を持ち、事前生成を基本とする」

/// 三角形網が保持する頂点の列の中の位置。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 三角形網の頂点の番号(usize);

impl 三角形網の頂点の番号 {
    /// 列の中の位置から作る。範囲に収まるかは、頂点の列を持つ三角形網の生成が確かめる。
    pub fn 生成する(列の中の位置: usize) -> Self {
        Self(列の中の位置)
    }

    /// 列の中の位置。
    pub fn 列の中の位置(&self) -> usize {
        self.0
    }
}

/// 三角形網が保持する三角形の列の中の位置。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 三角形網の三角形の番号(usize);

impl 三角形網の三角形の番号 {
    /// 列の中の位置から作る。範囲に収まるかは、三角形の列を持つ三角形網の生成が確かめる。
    pub fn 生成する(列の中の位置: usize) -> Self {
        Self(列の中の位置)
    }

    /// 列の中の位置。
    pub fn 列の中の位置(&self) -> usize {
        self.0
    }
}
