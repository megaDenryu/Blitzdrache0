//! 三角形網を作るときと、三角形網へ問い合わせるときに破れる条件。
//!
//! 生成の破れと問い合わせの破れを別の型にするのは、直す場所が違うためである。生成の破れは網のもとになるデータを
//! 直すことでしか消えず、問い合わせの破れは問い合わせの入力か、階層の組み立てを直すことで消える。
//!
//! 頂点の有限性と成分の絶対値の上限はここに無い。それは`形の局所座標の位置`の生成が守っており、位置を作れた
//! 時点で満たされているためである。

use thiserror::Error;

use crate::triangle::三角形の問い合わせエラー;

use super::number::{三角形網の三角形の番号, 三角形網の頂点の番号};

/// 三角形網の生成が拒む理由。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 三角形網の生成エラー {
    /// 三角形が1件も無かった。
    #[error("三角形網に三角形が1件も無い")]
    三角形が1件も無い,
    /// 三角形が持つ頂点の番号が、頂点の列の範囲の外を指していた。
    #[error("三角形網の{}番目の三角形が、頂点の列の外の頂点{}を指している", .三角形の番号.列の中の位置(), .頂点の番号.列の中の位置())]
    頂点の番号が頂点の列の外を指している {
        /// 範囲の外を指していた三角形の番号。
        三角形の番号: 三角形網の三角形の番号,
        /// 範囲の外を指していた頂点の番号。
        頂点の番号: 三角形網の頂点の番号,
    },
    /// 三角形の面積が零であり、面の平面と向きが定まらなかった。
    #[error("三角形網の{}番目の三角形の面積が零である", .三角形の番号.列の中の位置())]
    三角形の面積が零 {
        /// 面積が零であった三角形の番号。
        三角形の番号: 三角形網の三角形の番号,
    },
    /// 階層の組み立てが、辿れる深さの上限を越えた。
    #[error("三角形網の階層の深さが上限を越えた")]
    階層の深さが上限を越えている,
}

/// 三角形網への問い合わせで破れる条件。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 三角形網の問い合わせエラー {
    /// 葉の三角形1枚への詳細判定が失敗した。
    #[error("三角形網の中の三角形への問い合わせが失敗した: {0}")]
    三角形への問い合わせが失敗した(#[from] 三角形の問い合わせエラー),
    /// 階層を辿るスタックが上限を越えた。木の深さが上限に収まることを組み立てが保証するため、到達したら階層が壊れている。
    #[error("三角形網の階層を辿るスタックが上限を越えた")]
    走査のスタックが上限を越えている,
}
