//! 頂点の番号で表した三角形: 三角形網の中の1枚を、頂点の位置ではなく頂点の番号3つで表したものである。
//!
//! 位置で持つ`局所座標の三角形`と別の型にするのは、網が同じ頂点を何枚もの三角形で共有するためである。位置で
//! 持つと、共有する頂点が枚数だけ複製され、片方だけを動かした食い違いが作れてしまう。番号で持てば頂点は1つで
//! あり、動かす口も1つになる。
//!
//! 番号の並びが面に垂直な向きを決める。網を焼く側がその並びを決め、この型は並びをそのまま保つ。

use crate::shape::三角形の頂点の番号;

use super::number::三角形網の頂点の番号;

/// 三角形網の中の1枚を、頂点の番号3つで表したもの。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 頂点の番号で表した三角形 {
    頂点の番号: [三角形網の頂点の番号; 3],
}

impl 頂点の番号で表した三角形 {
    /// 3つの頂点の番号から作る。番号が頂点の列の範囲に収まるかは、三角形網の生成が確かめる。
    pub fn 三つの頂点の番号から生成する(頂点の番号: [三角形網の頂点の番号; 3]) -> Self {
        Self { 頂点の番号 }
    }

    /// 三角形の中の番号が指す頂点の、網の頂点の列の中での番号。
    pub fn 頂点の番号(&self, 三角形の中の番号: 三角形の頂点の番号) -> 三角形網の頂点の番号 {
        self.頂点の番号[三角形の中の番号.並びの位置()]
    }
}
