//! 三角形網へのカプセルの掃引の問い合わせ。受け取るのは掃引するカプセル、返すのは最も早く触れた三角形と
//! その接触である。
//!
//! 覆いは、軸の両端に外接する箱を半径ぶん広げ、掃引の変位で掃いた範囲である。広げる操作と掃く操作は端に丸めを
//! 入れるため、どちらも幅を外向きへ足した箱を返す(`crates/blitz_collision/src/shape/local_box_cover.rs`)。
//! 覆いの端が内側へ入ると、覆いに真に触れている三角形が候補から落ち、当たりが在るのに無いと答える。
//!
//! 候補1枚ごとに三角形のカプセルの掃引の問い合わせを組み、動けた割合の最も小さい接触を選ぶ。割合が並んだときは
//! 走査が先に渡した三角形を残す。掃引の始まりで既に触れている三角形が複数ある場合は、どれも割合0で並ぶため、
//! 走査の順で最初に出た1枚が答えになる。この層が返すのは1つの接触であり、接触点の集合を作るのは実装順10である。

use crate::shape::{局所座標の軸平行の直方体, 形を掃引するカプセル};
use crate::solver::最も小さい量の候補だけを覚える器;
use crate::triangle::{カプセルが三角形に最初に触れる点, 三角形のカプセルの掃引の問い合わせ};

use super::covering_scan::覆いに触れる三角形の走査;
use super::error::三角形網の問い合わせエラー;
use super::mesh::三角形網;
use super::mesh_contact::{カプセルが三角形網に最初に触れる点, 掃引したカプセルの三角形網への接触};

impl 三角形網 {
    /// 掃引したカプセルが網の三角形に最初に触れる点を求める。接触が無い場合と、最も早い接触を持つ場合を返す。
    pub fn カプセルが三角形網に最初に触れる点を求める(
        &self,
        カプセル: &形を掃引するカプセル,
    ) -> Result<カプセルが三角形網に最初に触れる点, 三角形網の問い合わせエラー> {
        let 覆い = 局所座標の軸平行の直方体::二点に外接する箱を求める(カプセル.軸の始点(), カプセル.軸の終点())
            .全方向へ広げた箱を求める(カプセル.半径のメートル())
            .変位で掃いた箱を求める(カプセル.掃引の変位());
        let mut 走査 = 覆いに触れる三角形の走査::根から始める(self.境界の木(), 覆い);
        let mut 最小 = 最も小さい量の候補だけを覚える器::まだ何も無い状態から始める();
        while let Some(三角形の番号) = 走査.次の三角形の番号を取り出す()? {
            let 問い合わせ = 三角形のカプセルの掃引の問い合わせ::三角形から生成する(self.三角形の幾何を読む(三角形の番号))?;
            if let カプセルが三角形に最初に触れる点::三角形に触れる(接触) =
                問い合わせ.カプセルが三角形に最初に触れる点を求める(カプセル)?
            {
                最小.候補を1つ数える(接触.動けた割合().値(), 掃引したカプセルの三角形網への接触::生成する(三角形の番号, 接触));
            }
        }
        Ok(match 最小.覚えている候補を取り出す() {
            Some(接触) => カプセルが三角形網に最初に触れる点::三角形網に触れる(接触),
            None => カプセルが三角形網に最初に触れる点::三角形網に触れない,
        })
    }
}
