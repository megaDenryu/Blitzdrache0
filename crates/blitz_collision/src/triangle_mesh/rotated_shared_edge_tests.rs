//! 回転した共有辺の両側からの当たりの反証。共有辺のちょうど上を狙う線分と掃引が、2枚のうちどちらかで必ず
//! 当たることを見る。取り逃せば、そこは網に開いた穴であり、辺のちょうど上を通った移動が形をすり抜ける。
//!
//! 辺の符号を厳密な0だけで特徴に分ける方式では、2枚の三角形が同じ辺について別々に符号を求める。回転で頂点が
//! 2進で割り切れない値になると、その2つの符号は別々に丸められ、どちらも負に出れば両方が当たらないと答える。
//! この反証はその割れが起きないことを、共有辺を65点に等分した全部の標本で確かめる。
//!
//! 平らな2枚と谷に折れた2枚の両方を見るのは、割れの起き方が違うためである。平らな2枚は同じ平面に乗るので、
//! 平面を横切る時刻がほぼ同じところに出て、辺の符号の丸めだけが勝負になる。折れた2枚は平面が別であるから、
//! 横切る時刻からして別々に出る。
//!
//! 線分の2つの反証は現に落ちる。共有辺を64等分した130本の線分のうち、平らな2枚で7本、谷に折れた2枚で13本が
//! どちらの三角形にも当たらない。落ちる標本では、辺の符号が両方の三角形で負の側の丸めに出る。実測した1件では
//! 一方が10のマイナス18乗、他方が10のマイナス17乗の負であり、その点での符号の自然な大きさ(辺の長さかける
//! 頂点からの隔たりかける面に垂直な変位の長さ)のおよそ10のマイナス16乗倍である。すなわち符号の値は倍精度の
//! 丸めの水面下に沈んでおり、厳密な零との比較では内外を決められない。
//!
//! 落ちる反証を`#[ignore]`で止めているのは、直し方の選択がこの反証の外にあるためである。選択が決まるまで
//! 検証の列を赤にしないためにここで止め、反証そのものは残す。直したら`#[ignore]`を外すことが受け入れの条件に
//! なる。掃引の反証は落ちないため止めていない。半径のぶんだけ判定が辺から離れた場所で決まるためである。
//!
//! 材料は`rotated_shared_edge_fixture.rs`が持つ。

use super::mesh::三角形網;
use super::mesh_contact::カプセルが三角形網に最初に触れる点;
use super::mesh_hit::線分が三角形網に最初に当たる点;
use super::query_fixture::{掃引の接触を求める, 線分の当たりを求める};
use super::rotated_shared_edge_fixture::{
    共有辺の上の標本の点, 回した平らな四角形の網, 回した折れた四角形の網, 点を局所座標へ写す
};

// 共有辺を等分する標本の総数。65点になるように64等分する。
const 共有辺の等分数: u32 = 64;

// 標本の点から天頂の向きへ離す長さ。網の広がりが1メートル級であるから、面を確実に挟む長さに取る。
const 面を挟む長さ: f64 = 0.5;

fn 天頂へずらした点(点: [f64; 3], 長さ: f64) -> [f64; 3] {
    [点[0], 点[1] + 長さ, 点[2]]
}

fn 共有辺の全部の標本で当たることを確かめる(網: &三角形網, 頂点: [[f64; 3]; 4], 何の網か: &str) {
    for 標本の番号 in 0..=共有辺の等分数 {
        let 点 = 共有辺の上の標本の点(頂点, 標本の番号, 共有辺の等分数);
        let 上 = 天頂へずらした点(点, 面を挟む長さ);
        let 下 = 天頂へずらした点(点, -面を挟む長さ);
        for (始点, 終点, どちらから) in [(上, 下, "上から"), (下, 上, "下から")] {
            assert!(
                matches!(線分の当たりを求める(網, 始点, 終点), 線分が三角形網に最初に当たる点::三角形網に当たる(_)),
                "{何の網か}の共有辺の標本{標本の番号}({:?})を{どちらから}狙った線分がどちらの三角形にも当たらなかった",
                点を局所座標へ写す(点)
            );
        }
    }
}

fn 共有辺の全部の標本で掃引が触れることを確かめる(網: &三角形網, 頂点: [[f64; 3]; 4], 何の網か: &str) {
    for 標本の番号 in 0..=共有辺の等分数 {
        let 点 = 共有辺の上の標本の点(頂点, 標本の番号, 共有辺の等分数);
        let 軸の位置 = 天頂へずらした点(点, 面を挟む長さ);
        let 掃引の変位 = [0.0, -2.0 * 面を挟む長さ, 0.0];
        assert!(
            matches!(
                掃引の接触を求める(網, 軸の位置, 0.05, 掃引の変位),
                カプセルが三角形網に最初に触れる点::三角形網に触れる(_)
            ),
            "{何の網か}の共有辺の標本{標本の番号}({:?})を狙った掃引がどちらの三角形にも触れなかった",
            点を局所座標へ写す(点)
        );
    }
}

#[test]
#[ignore = "辺の符号を厳密な零で見る方式では回した共有辺で割れが出る。直し方の選択が済んでいない"]
