//! 範囲を2つに分ける規則。受け取るのは範囲とその境界、返すのは分ける位置であり、あわせて範囲の中の三角形の
//! 番号を並べ替える。
//!
//! 組み立ての本体(`crates/blitz_collision/src/triangle_mesh/hierarchy_builder.rs`)と別に置くのは、これが
//! 「どこで分けるか」という1つの決定であり、木をどう積むかとは変わる理由が別だからである。分け方を差し替える
//! ときに触るのはこのファイルだけになる。
//!
//! 規則は2段である。分ける軸は境界の最も長い軸に取る。長い軸で分けると、子の境界がその軸で半分になり、
//! 問い合わせの覆いと交わらない子が増える。次にその軸に沿った三角形の境界の中央の座標で範囲を並べ替え、
//! ちょうど真ん中で切る。真ん中で切るのは、木の深さを件数の対数に抑えるためである。座標の値そのもので切ると、
//! 三角形が偏って集まった網で片側が空になり、深さが件数に比例しうる。
//!
//! 並べ替えの順は全順序である。中央の座標が同じ三角形は番号の小さい順に並ぶため、どの並べ替えの実装を使っても
//! 結果の並びは1つに決まる。中央の座標の比較に`total_cmp`を使うのは、有限でない値が来ても順序が定まる形にして
//! おくためである(頂点の位置が有限であるから中央も有限であり、実際には非有限は現れない)。

use std::cmp::Ordering;

use crate::shape::{局所座標の軸平行の直方体, 直方体自身の座標軸};

use super::hierarchy_builder::三角形網の階層の構築;
use super::node::葉が持つ三角形の範囲;
use super::number::三角形網の三角形の番号;

impl 三角形網の階層の構築 {
    // 範囲を2つに分ける位置。範囲の中の三角形の番号を並べ替えたうえで、範囲のちょうど中央の位置を返す。
    pub(super) fn 範囲を分ける位置を求める(
        &mut self, 範囲: 葉が持つ三角形の範囲, 境界: 局所座標の軸平行の直方体
    ) -> usize {
        let 軸 = 境界.最も長い軸を求める();
        let (三角形ごとの境界, 並べ替え) = self.三角形ごとの境界と並べ替えを別々に借りる();
        並べ替え[範囲.位置の範囲()]
            .sort_unstable_by(|一方, 他方| 二つの三角形を中央の座標で比べる(三角形ごとの境界, 軸, *一方, *他方));
        範囲.位置の範囲().start + 範囲.件数() / 2
    }
}

// 2つの三角形を、指定した軸に沿った境界の二つの三角形を中央の座標で比べる。座標が同じなら三角形の番号で比べ、順を1つに決める。
fn 二つの三角形を中央の座標で比べる(
    三角形ごとの境界: &[局所座標の軸平行の直方体],
    軸: 直方体自身の座標軸,
    一方: 三角形網の三角形の番号,
    他方: 三角形網の三角形の番号,
) -> Ordering {
    let 一方の中央 = 三角形ごとの境界[一方.列の中の位置()].軸に沿った中央のメートル(軸);
    let 他方の中央 = 三角形ごとの境界[他方.列の中の位置()].軸に沿った中央のメートル(軸);
    一方の中央.total_cmp(&他方の中央).then(一方.cmp(&他方))
}
