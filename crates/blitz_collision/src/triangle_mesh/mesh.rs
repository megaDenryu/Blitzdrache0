//! 三角形網: 頂点の列と、頂点の番号で表した三角形の列と、それらを包む境界の木を持つ静的な形である。
//!
//! 生成の入口は1つだけであり、頂点の列と三角形の列を同時に受け取る。片方ずつ受け取る形にしないのは、三角形の
//! 番号が頂点の列の範囲に収まるかを、両方が揃うまで検査できないためである。検査と階層の組み立ては生成の中で
//! 済み、完成した網には未解決の参照も未検査の値も残らない。
//!
//! 実行時形式(焼いた階層をそのまま読む形)はここに無い。それは物理アセット変換の担当である。この型が受け取るのは
//! メモリの上の2つの列だけであり、そこから階層をその場で組む。
//!
//! 頂点の有限性と成分の絶対値の上限は`形の局所座標の位置`の生成が守るため、ここでは検査し直さない。
//!
//! 三角形1枚ごとの面の向き(面に垂直な変位と単位法線の変位)を生成のときに求めて保持する。詳細判定はこの2つを
//! 必ず使うため、保持しなければ候補1枚につき外積と平方根を通し直すことになる。増えるメモリは三角形1枚につき
//! 倍精度6つの48バイトであり、頂点まで含めて持つ場合(120バイト)の半分以下である。頂点は頂点の列から番号で引く。

use crate::shape::{
    三角形の面の向き, 三角形の頂点の番号, 局所座標の三角形, 局所座標の軸平行の直方体, 形の局所座標の位置, 面の向きを備えた三角形
};

use super::error::三角形網の生成エラー;
use super::hierarchy::三角形網の境界の木;
use super::hierarchy_builder::三角形網の階層の構築;
use super::mesh_triangle::頂点の番号で表した三角形;
use super::mesh_validation::三角形ごとの幾何を組みながら検査する;
use super::number::三角形網の三角形の番号;

/// 頂点の列と三角形の列と境界の木を持つ、静的で複雑な形。
pub struct 三角形網 {
    頂点の位置: Vec<形の局所座標の位置>,
    三角形: Vec<頂点の番号で表した三角形>,
    三角形ごとの面の向き: Vec<三角形の面の向き>,
    境界の木: 三角形網の境界の木,
}

impl 三角形網 {
    /// 頂点の列と三角形の列から作る。三角形が1件も無い網・頂点の列の外を指す三角形・面積が零の三角形を
    /// 型付きエラーで拒み、通った三角形から境界の木をその場で組む。
    pub fn 頂点と三角形の列から生成する(
        頂点の位置: Vec<形の局所座標の位置>,
        三角形: Vec<頂点の番号で表した三角形>,
    ) -> Result<Self, 三角形網の生成エラー> {
        let 三角形ごとの幾何 = 三角形ごとの幾何を組みながら検査する(&頂点の位置, &三角形)?;
        let 三角形ごとの境界 = 三角形ごとの幾何.iter().map(三角形に外接する箱を求める).collect();
        let 三角形ごとの面の向き = 三角形ごとの幾何.iter().map(面の向きを備えた三角形::面の向き).collect();
        let 境界の木 = 三角形網の階層の構築::三角形ごとの境界から始める(三角形ごとの境界).木を組み上げる()?;
        Ok(Self {
            頂点の位置,
            三角形,
            三角形ごとの面の向き,
            境界の木,
        })
    }

    /// 網が持つ三角形の枚数。
    pub fn 三角形の件数(&self) -> usize {
        self.三角形.len()
    }

    /// 番号が指す三角形の、3つの頂点の位置。番号が列の中を指すことは生成の検査が保証する。
    pub fn 三角形の幾何を読む(&self, 三角形の番号: 三角形網の三角形の番号) -> 局所座標の三角形 {
        let 一枚 = self.三角形[三角形の番号.列の中の位置()];
        局所座標の三角形::三つの頂点から生成する(
            三角形の頂点の番号::並べる().map(|中の番号| self.頂点の位置[一枚.頂点の番号(中の番号).列の中の位置()]),
        )
    }

    /// 番号が指す三角形に、生成のときに求めた面の向きを添えたもの。詳細判定はこれを受け取り、外積も平方根も
    /// 通さずに問い合わせを組む。
    pub fn 面の向きを備えた三角形を読む(
        &self, 三角形の番号: 三角形網の三角形の番号
    ) -> 面の向きを備えた三角形 {
        面の向きを備えた三角形::面の向きを添えて生成する(
            self.三角形の幾何を読む(三角形の番号),
            self.三角形ごとの面の向き[三角形の番号.列の中の位置()],
        )
    }

    /// 網の全体を包む軸平行の直方体。階層の根の境界そのものである。
    pub fn 全体を包む箱を求める(&self) -> 局所座標の軸平行の直方体 {
        self.境界の木.節点を読む(self.境界の木.根の位置()).境界()
    }

    pub(super) fn 境界の木(&self) -> &三角形網の境界の木 {
        &self.境界の木
    }
}

// 三角形1枚を包む軸平行の直方体。頂点の位置の最小と最大を選ぶだけで丸めを1つも通さない。
fn 三角形に外接する箱を求める(三角形: &面の向きを備えた三角形) -> 局所座標の軸平行の直方体 {
    局所座標の軸平行の直方体::三点に外接する箱を求める(三角形の頂点の番号::並べる().map(|番号| 三角形.頂点の位置(番号)))
}
