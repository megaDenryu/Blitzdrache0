//! 静止したカプセルへの詳細判定。担当するのは、カプセルを掃引して、静止したもう1つのカプセルに最初に触れるまでを
//! 求める問い合わせである。
//!
//! 形そのもの(`crate::shape`のカプセル)と別のモジュールにするのは、形の表現が問い合わせの入力にも動く形の索引にも
//! 現れるのに対し、詳細判定が実行中の問い合わせにしか現れないためである。判定の側から形の側への依存だけがある。
//!
//! 数学の方式。動く軸の線分と静止した軸の線分の隔たりが2つの半径の和に等しくなる最小の時刻を、特徴の組ごとの
//! 2次方程式として解析的に解く。刻み探索も二分法も反復法も使わない。同じ入力が必ずビット単位で同じ答えを返す
//! ためである(`_doc/設計/世界の形と衝突基盤.md`「判断14: 決定性の維持」)。式は形の種類に依らない求解の部品
//! (`crates/blitz_collision/src/solver.rs`)から取り、ここには書き写さない。
//!
//! 直方体の掃引と違って、軸そのものが形を貫く場合を別に見ない。直方体は中身の詰まった立体であり、軸が中に居ると
//! 特徴ごとの最近接がどれも隔たり0に達しないのに対し、2つのカプセルが重なることは「2つの軸の隔たりが半径の和より
//! 小さい」ことと同じであり、9通りの候補がその隔たりそのものを数え上げるためである。線分どうしの隔たりは、
//! どちらかの端が相手に最も近いか、両方の内側で垂線の足が範囲に収まるかのどれかで達成される。
//!
//! 2つの軸がちょうど交わって隔たりが0になる入力では、押し戻す向きがこの層で決まらない。カプセルの軸の上の点は
//! 直方体の面のような外向きを持たず、どの向きへ押しても同じだけ離れるためである。この場合は型付きエラーで返し、
//! 向きを決める材料を持つ側へ委ねる。直方体の掃引が同じ理由で持つ枝と同じ扱いである。
//!
//! 座標系と丸め。2つのカプセルの軸の端は同じ1つの局所座標系に倍精度で来る。判定の演算はすべて倍精度で行い、
//! 単精度へ狭めるのは接触の単位法線を返す1箇所だけである。半径の和を作る加算の丸めが1回入り、その丸めは
//! 接触の隔たりの目標値を最終桁ぶんだけ動かす。動いた目標値に対する時刻のずれは、隔たりが時刻について
//! 変化する速さで割った量であり、正面から近づく掃引では半径の和の最終桁を掃引の速さで割った時間になる。
//!
//! 桁あふれ。位置と変位の成分の絶対値も半径も、形の座標と同じ上限(2の24乗メートル)に収まる。この上限をBと書くと、
//! 半径の和は2B以下、2つの軸の変位の成分は2B以下、静止した点から時刻の掃引する軸の端への変位の成分は3B以下で
//! ある。係数が最も大きく育つのは2つの軸の内側どうしの式であり、2つの軸の変位の外積の成分は8かけるBの二乗以下、
//! その長さの二乗は192かけるBの4乗以下になる。この向きへの射影で組んだ3つの係数は576かけるBの6乗・
//! 3456かけるBの6乗・5184かけるBの6乗以下であるから、判別式は23887872かけるBの12乗以下である。
//! B = 2の24乗ではBの12乗が2の288乗すなわちおよそ5.0かける10の86乗であるから、判別式の上界はおよそ
//! 1.2かける10の94乗であり、倍精度の最大値1.8かける10の308乗を大きく下回る。
//! 数え方の元は `crates/blitz_collision/src/height_field/length_limit.rs` にある。
//!
//! 桁落ち。半径は下限2のマイナス24乗メートルも守るため、半径の和の二乗は2のマイナス46乗以上であり、接触の
//! 隔たりが達すべき目標値が非正規化数へ落ちて0へ潰れることがない。下限が無いと、10のマイナス200乗メートル級の
//! 半径では目標値も隔たりの二乗も同時に0へ落ち、離れている対が掃引の始まりから触れているものとして返る。
//! 隔たりの二乗の側だけが0へ潰れる入力は残るが、それが起こるのは真の隔たりが半径の和の10の140乗分の1を
//! 下回るときであるから、触れていると判ずるその答えが正しい。下限とその算術は
//! `crates/blitz_collision/src/shape/capsule_radius_lower_limit.rs` にある。
//!
//! 押し戻す向きは、軸の上の最近接点から掃引する軸へ向かう変位を長さ1へ正して作る。正す工程が成分の尺度を
//! 最も大きい絶対値で揃えてから長さを求めるため、10のマイナス200乗メートル級の隔たりでも向きが定まる
//! (`crates/blitz_collision/src/shape/local_displacement_direction.rs`)。向きが定まらないのは3つの成分が
//! すべて0のとき、すなわち2つの軸がちょうど交わるときだけである。

