//! 三角形網: 静的で複雑な形を三角形の集まりとして持ち、階層で候補を絞ってから三角形1枚ずつの詳細判定へ渡す形である。
//!
//! **適する用途。** 静的で複雑な世界の形である。崖・洞窟・建物の細かい造作・大型の岩がこれに当たる。どれも
//! 単純形状の組で近似すると形が変わってしまい、しかも一度置いたら動かない。
//!
//! **適さない用途。** 動く剛体と、毎刻み大きく変形する形である。動く剛体には、姿勢だけが変わる単純形状か
//! その複合を使う。階層は組み立ての費用が三角形の件数に比例するうえ、形が変わるたびに組み直しになるためである。
//! 布や紐のように毎刻み頂点が動く形も同じ理由で対象外であり、そちらは動く物体向けの索引が別に要る
//! (`_doc/設計/世界の形と衝突基盤.md`「判断12」の実装順8)。
//!
//! **単純形状との使い分け。** 形が箱・球・カプセルの組で表せるなら、そちらを使う。詳細判定が解析式1本で済み、
//! 階層も要らないためである。三角形網を選ぶのは、面の並びそのものが形の意味を持つとき(足を置ける段差、頭を
//! ぶつける天井、通り抜けられる穴)に限る。建物の部品ごとの直方体で足りる範囲は、既に実装順4と5が扱っている。
//!
//! **事前生成が前提である。** 階層は、網を焼く側が1回組んで実行時形式へ書き出すことを基本とする。この型の生成も
//! 同じ組み立てをその場で行うが、それはチャンクを読み込むたびに走らせてよいという意味ではない。実行時形式と
//! その読み書きは物理アセット変換の担当であり、ここには無い。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断11: 静的衝突メッシュは階層を持ち、事前生成を基本とする」
//!
//! 階層が満たす不変条件は判断11が挙げた5つである。(1)各節点の境界は配下の全三角形を包む。境界は頂点の位置の
//! 最小と最大を選ぶだけで組むため丸めを1つも通さず、包みは厳密である。(2)葉は高々4枚の三角形へ到達する。
//! (3)組み立ては生成の1回だけであり、実行中に組み直さない。(4)網が住むのは形の局所座標系であり、世界座標へ写す
//! のは呼び出し側である。(5)階層はこのモジュールの外へ出ない。公開するのは網と、問い合わせの答えだけである。

