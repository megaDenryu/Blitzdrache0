//! 覆いを当たりのところまで切り詰める計算が端へ入れる丸めを、外から包む幅。受け取るのは切り詰めに関わる成分の値、
//! 返すのは軸ごとの幅である。幅を足し引きするのは`global_axis_aligned_box.rs`の切り詰めの2つの入口である。
//!
//! この幅が要るのは、切り詰めた端をそのままチャンクの座標へ写すと、真の端がチャンクの境界をちょうど踏むところで
//! 計算値が内側へ入り、未読込の隣のチャンクを矩形から外すためである。外れた矩形は読込済みのチャンクだけで埋まり、
//! 覆いは「対象範囲を完全に評価できた」と答える。その答えは見つけた当たりを確定として返してよいという判断へ
//! そのまま渡るため、確定でない当たりを確定と言う誤りになる。これは詳細判定でも取り返せない。
//!
//! 外へ広げすぎる側の害は、完全と言えたはずの縁の問い合わせを不完全と言うことだけである。その問い合わせは当たりを
//! 捨てて「何にも当たらない」の側で答えるため、確定でない当たりを確定と言うことは起きない。2つの誤りは重さが違う
//! ため、幅は誤差の上界の上からさらに安全側へ丸めて決める。
//!
//! 以下では倍精度の演算1回の相対誤差の上限である2の53乗分の1をuと書き、標準模型 fl(x∘y) = (x∘y)(1+δ)、δの絶対値は
//! u以下、を使う。係数は2次以上の項を吸収した整数にする。
//!
//! 線分の側の演算列は、端をa・もう一方の端をb・比をtとして、d = fl(b − a)、m = fl(d·t)、p = fl(a + m) である。
//! 真の点は P = a + (b − a)·t であり、3つの丸めをδ1・δ2・δ3と置くと
//! p − P = a·δ3 + (b − a)·t·[(1+δ1)(1+δ2)(1+δ3) − 1] になる。角括弧の中の絶対値は4u以下、|(b − a)·t| は
//! |a| + |b| 以下であるから、|p − P| は u·|a| + 4u·(|a| + |b|)以下、すなわち 5u·(|a| + |b|) 以下である。
//!
//! 掃引の側の演算列は、掃く前の箱の端をe・変位の成分をD・比をtとして、m = fl(D·t)、q = fl(e + m) である。Dは単精度
//! からの変換であり丸めを通らない。真の端は Q = e + D·t であり、q − Q = e·δ2 + D·t·[(1+δ1)(1+δ2) − 1] になる。
//! 角括弧の中の絶対値は3u以下、|D·t| は計算した移動の絶対値の(1+2u)倍以下であるから、|q − Q| は
//! 4u·(|e| + |移動|) 以下である。eは箱の2つの端のどちらにもなるため、幅は2つの端の絶対値の和で押さえる。
//!
//! したがって幅は、線分の側では |a| + |b| に、掃引の側では掃く前の箱の2つの端と移動の絶対値の和に、どちらも
//! 2の49乗分の1(16u)を掛けた値にする。16uを選ぶのは、上の上界(線分は5u、掃引は4u)を3倍以上上回り、そのうえで
//! 絶対値の和を求める加算の丸め(uの1倍)と端へ幅を足し引きする加算の丸め(uの1倍あまり)を足しても、なお上界を
//! 上回るためである。2の冪を掛ける積は丸めを通らないため、相対量そのものは誤差を持ち込まない。
//!
//! 定義域。端の絶対値は、形状の座標の上限である2の24乗メートルに、チャンクの基準原点の大きさを足した範囲に収まる。
//! 基準原点はチャンクの座標(32ビット整数)とチャンクの一辺の積であるから、和は2の40乗メートルの桁を出ない。この
//! 範囲では絶対値の和も幅も倍精度の正規化数に収まり、桁あふれも非正規化数への落ち込みも起きない。範囲を大きく出た
//! 値が来て和が桁あふれした場合、幅は無限大になって端も有限でなくなるが、その端はチャンクの座標へ写す入口が
//! 型付きエラーで拒む。黙って内側へ縮む側には落ちない。
//! 参照: `crates/blitz_collision/src/shape/global_axis_aligned_box.rs`

// 端の絶対値の和に掛ける相対量。2の49乗分の1である。
const 切り詰めの丸めを包む幅の相対量: f64 = 1.0 / 562_949_953_421_312.0;

// 線分を比のぶんだけ進めた端が受ける丸めを外から包む幅。線分の両端の成分から軸ごとに決まる。
pub(super) fn 線分の切り詰めが受ける丸めを包む幅を求める(端: [f64; 3], もう一方の端: [f64; 3]) -> [f64; 3] {
    [0usize, 1, 2].map(|軸| (端[軸].abs() + もう一方の端[軸].abs()) * 切り詰めの丸めを包む幅の相対量)
}

// 掃引の端を比のぶんだけ動かした端が受ける丸めを外から包む幅。掃く前の箱の両端と、比を掛けた移動から軸ごとに決まる。
pub(super) fn 掃引の切り詰めが受ける丸めを包む幅を求める(
    掃く前の最小の端: [f64; 3],
    掃く前の最大の端: [f64; 3],
    移動: [f64; 3],
) -> [f64; 3] {
    [0usize, 1, 2]
        .map(|軸| (掃く前の最小の端[軸].abs() + 掃く前の最大の端[軸].abs() + 移動[軸].abs()) * 切り詰めの丸めを包む幅の相対量)
}
