//! 形の局所座標の変位を、形の種類に依らない求解の部品が扱える変位として見せるトレイト実装。
//!
//! 型自身の演算と別のファイルへ置くのは、こちらが外部トレイトの実装であり、型の定義とは変わる理由が別だからである。
//! 実装が既にある演算をそのまま渡すだけであるのは、能力の名前を型の側の名前に合わせて数え上げたためである。
//! 参照: `crates/blitz_collision/src/solver.rs`

use super::local_displacement::形の局所座標の変位;
use crate::solver::求解が扱う変位;

impl 求解が扱う変位 for 形の局所座標の変位 {
    fn 内積(self, 相手: Self) -> f64 {
        形の局所座標の変位::内積(self, 相手)
    }

    fn 外積(self, 相手: Self) -> Self {
        形の局所座標の変位::外積(self, 相手)
    }

    fn 長さの二乗(self) -> f64 {
        形の局所座標の変位::長さの二乗(self)
    }
}
