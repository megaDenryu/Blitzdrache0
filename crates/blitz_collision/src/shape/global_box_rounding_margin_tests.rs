//! 箱の端を組む計算の丸めが、真の端を箱の外へ置き去りにしないことの反証。切り詰めでない全体の覆いを組む2つの
//! 操作、すなわち半径ぶん広げる操作と変位で掃く操作に加えて、局所の箱を大域原点から写す操作を見る。
//!
//! 端を組む加算は最近接へ丸めるため、丸めた端は真の端の内側へ落ちうる。覆いの側で内側へ落ちた端は、真の端が
//! チャンクの境界をちょうど踏む入力で未読込の隣のチャンクを矩形から外し、完全でない覆いを完全と答えさせる元になる。
//! 写した子形状の箱の側で内側へ落ちた端は、覆いに真に触れている子形状を候補から落とす元になる。ここで見るのは
//! その手前にある「箱の端が真の端を外から包む」ことそのものである。
//!
//! 覆いの入力は、広げる前の端を1に2の52乗分の1を足した値、広げる長さと掃く距離を63メートルに取る。真の和は
//! 64に2の52乗分の1を足した値であり、64以上128未満の刻み(2の46乗分の1)では表せないため、丸めた端はちょうど
//! 64.0になる。幅を足さなければ端は真の端より2の52乗分の1メートルだけ内側に立つ。
//!
//! 写す側の入力は、大域原点を2の36乗メートル(一辺64メートルのチャンクの座標では2の30乗、32ビット整数に収まる)、
//! 局所の箱の端を1に単精度の刻み(2の23乗分の1)を足した値のプラスとマイナスに取る。真の和は2の36乗を1だけ離れた
//! 整数から2の23乗分の1だけ外れた値であり、その桁の刻み(2の16乗分の1と2の17乗分の1)では表せないため、丸めた端は
//! 両側ともちょうど整数になる。幅を足さなければ端は真の端より2の23乗分の1メートルだけ内側に立つ。
//! 参照: `crates/blitz_collision/src/shape/cover_rounding_margin.rs`

use blitz_math::{メートル, ローカル, ワールド, 位置, 変位, 大域メートル, 大域ワールド位置, 方向};

use super::axis_aligned_box::軸平行の直方体;
use super::global_axis_aligned_box::大域の軸平行の直方体;

const 真の端が丸めた端を越える量: f64 = f64::EPSILON; // 2の52乗分の1メートル。1と次の倍精度との差である
const 広げる前の東: f64 = 1.0 + 真の端が丸めた端を越える量; // 1の刻みで表せるため和は丸めを通らない
const 東へ動かす長さメートル: f32 = 63.0;
const 丸めた端: f64 = 64.0;

fn 東の座標だけを与えた位置(東: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(東), 大域メートル::生成する(0.0), 大域メートル::生成する(0.0))
}

fn 東へ進む変位(メートル数: f32) -> 変位<ワールド> {
    let 東 = match 方向::<ワールド>::生成する(1.0, 0.0, 0.0) {
        Ok(方向) => 方向,
        Err(誤り) => panic!("試験用の方向を作れなかった: {誤り}"),
    };
    変位::方向へ進む(東, メートル::生成する(メートル数))
}

// 丸めた端と真の端の差は倍精度でちょうど表せるため、引き算そのものは誤差を持ち込まない。
fn 東の端が真の端を外から包むことを確かめる(覆い: &大域の軸平行の直方体) {
    assert_eq!(
        広げる前の東 + f64::from(東へ動かす長さメートル),
        丸めた端,
        "丸めが端を内側へ動かす入力である"
    );
    assert!(
        覆い.最大の端().x().値() - 丸めた端 >= 真の端が丸めた端を越える量,
        "東の端が真の端の内側に立っている"
    );
}

#[test]
fn 半径ぶん広げた東の端は丸めで真の端の内側へ落ちない() {
    let 点 = 東の座標だけを与えた位置(広げる前の東);
    let 覆い =
        大域の軸平行の直方体::二点に外接する箱を求める(点, 点).全方向へ広げた箱を求める(メートル::生成する(東へ動かす長さメートル));
    東の端が真の端を外から包むことを確かめる(&覆い);
}

#[test]
fn 変位で掃いた東の端は丸めで真の端の内側へ落ちない() {
    let 点 = 東の座標だけを与えた位置(広げる前の東);
    let 覆い = 大域の軸平行の直方体::二点に外接する箱を求める(点, 点).変位で掃いた箱を求める(東へ進む変位(東へ動かす長さメートル));
    東の端が真の端を外から包むことを確かめる(&覆い);
}

const 写す大域原点の東: f64 = 68_719_476_736.0; // 2の36乗メートル。一辺64メートルのチャンクの座標では2の30乗である
const 写す局所の端の東: f32 = 1.0 + f32::EPSILON; // 1の刻みで表せるため単精度のままでも丸めを通らない
const 写して丸めた最大の端: f64 = 68_719_476_737.0;
const 写して丸めた最小の端: f64 = 68_719_476_735.0;
const 写した真の端が丸めた端を越える量: f64 = 1.0 / 8_388_608.0; // 2の23乗分の1メートル。単精度の1と次の値との差である

fn 東の値を3成分に置いた局所の位置(東: f32) -> 位置<ローカル> {
    位置::生成する(メートル::生成する(東), メートル::生成する(東), メートル::生成する(東))
}

#[test]
fn 大域原点から写した東の両端は丸めで真の端の内側へ落ちない() {
    let 局所の箱 = match 軸平行の直方体::二つの端から生成する(
        東の値を3成分に置いた局所の位置(-写す局所の端の東),
        東の値を3成分に置いた局所の位置(写す局所の端の東),
    ) {
        Ok(箱) => 箱,
        Err(誤り) => panic!("試験用の局所の箱を作れなかった: {誤り}"),
    };
    let 写した =
        大域の軸平行の直方体::局所の箱を大域原点から写して求める(東の座標だけを与えた位置(写す大域原点の東), &局所の箱);
    assert_eq!(
        写す大域原点の東 + f64::from(写す局所の端の東),
        写して丸めた最大の端,
        "丸めが最大の端を内側へ動かす入力である"
    );
    assert_eq!(
        写す大域原点の東 - f64::from(写す局所の端の東),
        写して丸めた最小の端,
        "丸めが最小の端を内側へ動かす入力である"
    );
    assert!(
        写した.最大の端().x().値() - 写して丸めた最大の端 >= 写した真の端が丸めた端を越える量,
        "東の最大の端が真の端の内側に立っている"
    );
    assert!(
        写して丸めた最小の端 - 写した.最小の端().x().値() >= 写した真の端が丸めた端を越える量,
        "東の最小の端が真の端の内側に立っている"
    );
}
