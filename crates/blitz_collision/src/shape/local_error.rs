//! 形の局所座標の位置と変位を作るときに破れる条件。
//!
//! 直方体の生成エラーと別の型にするのは、あちらが形そのものが成り立つかを言うのに対し、こちらは形へ
//! 問い合わせる側が渡す点と向きが扱える範囲に在るかを言うためである。同じ枝へ混ぜると、形が壊れているのか
//! 問い合わせが壊れているのかを呼び出し側が区別できない。

use thiserror::Error;

use super::coordinate_limit::形状の座標の絶対値の上限メートル;

/// 形の局所座標の位置と変位を作るときに破れる条件。成分の有限性と、成分の絶対値の上限の2つである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 形の局所座標の生成エラー {
    /// 位置の3成分のどれかが有限でない値だった。
    #[error("形の局所座標の位置の成分に有限でない値が含まれる")]
    位置の成分が有限でない,
    /// 位置の3成分のどれかが、桁あふれを避けるために課した座標の絶対値の上限を越えていた。
    #[error("形の局所座標の位置の成分の絶対値が上限{}メートルを越えた", 形状の座標の絶対値の上限メートル)]
    位置の成分の絶対値が上限を越えている,
    /// 変位の3成分のどれかが有限でない値だった。
    #[error("形の局所座標の変位の成分に有限でない値が含まれる")]
    変位の成分が有限でない,
    /// 変位の3成分のどれかが、桁あふれを避けるために課した座標の絶対値の上限を越えていた。
    #[error("形の局所座標の変位の成分の絶対値が上限{}メートルを越えた", 形状の座標の絶対値の上限メートル)]
    変位の成分の絶対値が上限を越えている,
}
