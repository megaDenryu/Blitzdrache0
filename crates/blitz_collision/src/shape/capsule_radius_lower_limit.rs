//! カプセルの半径が守る絶対値の下限。形の座標の絶対値の上限の逆数として定めるため、2のマイナス24乗メートル
//! すなわちおよそ60ナノメートルである。
//!
//! 下限を課すのは、求解が作る半径の和の二乗が非正規化数へ落ちないことを保証するためである。非正規化数とは、
//! 指数がこれ以上小さくならないところで仮数の桁を削って表す値であり、その二乗はほとんどの場合0へ潰れる。
//! 下限をrと書くと2つのカプセルの半径の和は2r以上であるから、その二乗は4かけるrの二乗すなわち
//! 2のマイナス46乗以上になる。倍精度の正規化数の最小が2のマイナス1022乗であるから、接触の隔たりが達すべき
//! 目標値は常に正規化数に収まる。
//!
//! 下限が無いと目標値そのものが0へ潰れ、答えが逆になる。半径が10のマイナス200乗メートルの2つの球を
//! 3かける10のマイナス200乗メートル離して置くと、実際の隔たりは半径の和より大きく触れていないのに、
//! 隔たりの二乗も半径の和の二乗もどちらも0へ落ちるため、掃引の始まりから触れているものとして扱われる。
//!
//! 下限を課した後も、隔たりの二乗や外積の長さの二乗が非正規化数へ落ちること自体は起こりうる。それが起こるのは
//! 真の隔たりが1.5かける10のマイナス154乗メートルを下回るときであり、半径の和が2のマイナス23乗メートル以上で
//! ある以上、隔たりは半径の和の10の140乗分の1を下回る。すなわちそのとき「触れている」と判ずるのが正しい答えで
//! あり、二乗が0へ潰れた比較はその正しい答えをそのまま返す。
//!
//! 軸の長さが同じように小さい場合は下限が守らない。軸の変位の長さの二乗が0へ落ちたカプセルでは、軸の内側の
//! 候補が値なしを返して端の候補だけが答える。軸の両端が10のマイナス154乗メートルより近いカプセルは球と
//! 区別が付かないため、球として答えるその結果が正しい。
//!
//! 下限が実用を狭めないのは、60ナノメートル未満の半径がゲームの物理で意味を持たないためである。1メートルの
//! ところでの単精度の刻みが119ナノメートルであり、形の姿勢も描画の位置もその刻みより細かくは表せない。
//!
//! 上限と下限を同じ指数の対称に置くのは、二乗・4乗・積を重ねる算術の桁あふれと桁落ちを1つの枠で語るためである。
//! 上限とその算術は `crates/blitz_collision/src/shape/coordinate_limit.rs` にある。

use super::coordinate_limit::形状の座標の絶対値の上限メートル;

