//! 形の局所座標の変位を、長さ1に正した単精度の方向へ狭める工程。倍精度で導いた向きが単精度へ狭まる境界が
//! ここ1箇所である。
//!
//! 型の定義と別のファイルへ置くのは、こちらが`blitz_math`の`方向`という外部の型へ渡す境界であり、
//! 型そのものの代数とは変わる理由が別だからである。3つの成分がすべて0の変位は向きを持たないため値なしで答え、
//! 呼び出し側が代わりの向き(面の外向き法線など)を選ぶ。
//!
//! 長さを求める前に成分の尺度を揃えるのは、10のマイナス200乗メートル級の変位で長さの二乗が0へ潰れ、向きの
//! 定まる入力が「向きが無い」として返ることを防ぐためである。カプセルどうしの詳細判定はその値なしを
//! 「2つの軸がちょうど交わる」と読んで型付きエラーを返すため、潰れた長さは中心の異なる2つの球を交わったものと
//! 偽ることになる。
//!
//! 狭めた向きの成分は単精度の刻みぶん真値からずれる。形の回転そのものが単精度で焼かれているため、
//! 向きの精度をこれ以上上げても形の側の精度を越えられない。長さの正しさは`方向`の生成が確かめる。

use blitz_math::{方向, 方向エラー, 空間};

use super::local_displacement::形の局所座標の変位;

impl 形の局所座標の変位 {
    /// 長さを1に正してから単精度の方向へ狭める。すべての成分が0の変位と有限でない成分を持つ変位は、向きを
    /// 持たないため値なしを返す。
    pub fn 長さで正した方向へ狭める<空間種: 空間>(&self) -> Option<Result<方向<空間種>, 方向エラー>> {
        Some(self.長さで正した変位を求める()?.正した変位を方向へ狭める())
    }

    // 長さを1に正した同じ向きの変位。すべての成分が0の変位と有限でない成分を持つ変位は値なしを返す。
    // 正した変位そのものを返す入口があるのは、接触の位置を「軸の上の点からこの向きへ半径だけ進めた点」として
    // 倍精度で組む側が要るためである。単精度へ狭めた向きから組み直すと、位置が半径に単精度の刻みを掛けた分だけずれる。
    // 成分を最も大きい絶対値で割ってから長さを求めるため、割った後の最大の成分はちょうど1になり、長さの二乗は
    // 1以上3以下に収まる。非正規化数へも無限大へも達しないので、非零の変位からは必ず向きが定まる。
    // 割り算が1回増えるぶん成分の相対誤差が丸めの単位1つぶん育つが、単位方向の生成が見る長さの許容差(千分の1)を
    // 大きく下回る。
    pub(crate) fn 長さで正した変位を求める(self) -> Option<Self> {
        let 成分 = [self.xのメートル(), self.yのメートル(), self.zのメートル()];
        if 成分.into_iter().any(|値| !値.is_finite()) {
            return None;
        }
        let 最も大きい絶対値 = 成分.into_iter().fold(0.0_f64, |これまでの最大, 値| これまでの最大.max(値.abs()));
        if 最も大きい絶対値 <= 0.0 {
            return None;
        }
        let 尺度を揃えた = Self::演算の結果から組む(成分[0] / 最も大きい絶対値, 成分[1] / 最も大きい絶対値, 成分[2] / 最も大きい絶対値);
        let 長さ = 尺度を揃えた.長さの二乗().sqrt();
        Some(Self::演算の結果から組む(
            尺度を揃えた.xのメートル() / 長さ,
            尺度を揃えた.yのメートル() / 長さ,
            尺度を揃えた.zのメートル() / 長さ,
        ))
    }

    // 前提: 長さが既に1に正されている。正していない変位を渡すと、方向の生成が長さの検査で型付きエラーを返す。
    pub(crate) fn 正した変位を方向へ狭める<空間種: 空間>(self) -> Result<方向<空間種>, 方向エラー> {
        方向::倍精度の成分から生成する(self.xのメートル(), self.yのメートル(), self.zのメートル())
    }
}
