//! 任意姿勢の直方体の倍精度の幾何: 単精度で持つ直方体を、中心と3本の単位軸と軸ごとの半分の長さという
//! 倍精度の形に読み直したものである。
//!
//! 呼び出しタイミング: 外接する軸平行の直方体の合成と、線分・カプセルとの詳細判定のそれぞれが、
//! 相手の形1つにつき1回組む。
//!
//! 倍精度で読み直すのは2つの理由による。1つは、単精度で組むと丸めの絶対誤差が半分の長さに比例して残り、
//! 真の広がりがそれよりはるかに小さい姿勢(長い半軸がほぼ直交へ回った箱)で結果が誤差に埋もれるためである。
//! もう1つは、問い合わせの点が大域の倍精度で来るため、形の側を単精度のまま扱うと点の側を先に狭めることに
//! なるためである。
//!
//! 四元数を倍精度で正規化してから軸を組むのは、単精度で正規化された四元数の長さが倍精度で見ると1から
//! 単精度の刻みぶん離れており、そのずれが軸の成分を通って半分の長さに比例した誤差になるためである。
//! ここで割れば残るのは倍精度の丸めだけになる。長さが零にならないことは四元数の型が不変条件として保証する。
//!
//! この幾何を合成と詳細判定の両方が通るため、外接する箱が包む形と、当たりを調べる形が同じ1つの読み方になる。

use blitz_math::{クォータニオン, ローカル};

use super::box_axis::直方体自身の座標軸;
use super::local_displacement::形の局所座標の変位;
use super::local_position::形の局所座標の位置;
use super::oriented_box::任意姿勢の直方体;

/// 単精度で持つ直方体を、中心と3本の単位軸と軸ごとの半分の長さという倍精度の形に読み直したもの。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 任意姿勢の直方体の倍精度の幾何 {
    中心: 形の局所座標の位置,
    軸ごとの単位向き: [形の局所座標の変位; 3],
    軸ごとの半分の長さのメートル: [f64; 3],
}

impl 任意姿勢の直方体の倍精度の幾何 {
    /// 直方体から読み直す。中心も半分の長さも直方体の生成が有限性と上限を確かめているため、ここに検査は無い。
    pub fn 直方体から組む(直方体: &任意姿勢の直方体) -> Self {
        let 中心の成分 = [直方体.中心().x(), 直方体.中心().y(), 直方体.中心().z()].map(|成分| f64::from(成分.値()));
        let 行列 = 倍精度で正規化した四元数から回転行列を組む(直方体.回転());
        let 半分 = [
            直方体.軸ごとの半分の長さ().x(),
            直方体.軸ごとの半分の長さ().y(),
            直方体.軸ごとの半分の長さ().z(),
        ]
        .map(|長さ| f64::from(長さ.値()));
        Self {
            中心: 形の局所座標の位置::検査済みの成分から組む(中心の成分[0], 中心の成分[1], 中心の成分[2]),
            軸ごとの単位向き: [0usize, 1, 2]
                .map(|列| 形の局所座標の変位::演算の結果から組む(行列[0][列], 行列[1][列], 行列[2][列])),
            軸ごとの半分の長さのメートル: 半分,
        }
    }

    /// 局所座標系における直方体の中心。
    pub fn 中心(&self) -> 形の局所座標の位置 {
        self.中心
    }

    /// 直方体自身の1本の軸を、局所座標系で表した長さ1の変位。
    pub fn 軸に沿った単位向き(&self, 軸: 直方体自身の座標軸) -> 形の局所座標の変位 {
        self.軸ごとの単位向き[軸.並びの位置()]
    }

    /// 直方体自身の1本の軸に沿った、中心から面までの長さであるメートル。
    pub fn 軸に沿った半分の長さのメートル(&self, 軸: 直方体自身の座標軸) -> f64 {
        self.軸ごとの半分の長さのメートル[軸.並びの位置()]
    }

    // 直方体自身の3軸に沿った半分の長さを局所座標系へ回し、成分ごとに絶対値を足し合わせた広がり。
    // 中心へこれを足し引きした区間が、直方体を包む軸平行の直方体の端になる。
    pub(super) fn 軸ごとの広がりを求める(&self) -> [f64; 3] {
        let 半分 = self.軸ごとの半分の長さのメートル;
        let 軸 = self
            .軸ごとの単位向き
            .map(|向き| [向き.xのメートル(), 向き.yのメートル(), 向き.zのメートル()]);
        [0usize, 1, 2].map(|成分| 軸[0][成分].abs() * 半分[0] + 軸[1][成分].abs() * 半分[1] + 軸[2][成分].abs() * 半分[2])
    }

    // 軸ごとの半分の長さを足し合わせた量。外接する箱の端へ足す余白の基準になる尺度である。
    pub(super) fn 半分の長さの総和を求める(&self) -> f64 {
        self.軸ごとの半分の長さのメートル.into_iter().sum()
    }
}

// 四元数の4成分を倍精度へ広げ、長さで割ってから回転行列の成分を組む。行列の第k列が、直方体自身の第k軸を
// 局所座標系で表した向きである。
fn 倍精度で正規化した四元数から回転行列を組む(回転: クォータニオン<ローカル, ローカル>) -> [[f64; 3]; 3] {
    let [生のx, 生のy, 生のz, 生のw] = 回転.境界用xyzw配列().map(f64::from);
    let 長さ = (生のx * 生のx + 生のy * 生のy + 生のz * 生のz + 生のw * 生のw).sqrt();
    let (x, y, z, w) = (生のx / 長さ, 生のy / 長さ, 生のz / 長さ, 生のw / 長さ);
    [
        [1.0 - 2.0 * (y * y + z * z), 2.0 * (x * y - z * w), 2.0 * (x * z + y * w)],
        [2.0 * (x * y + z * w), 1.0 - 2.0 * (x * x + z * z), 2.0 * (y * z - x * w)],
        [2.0 * (x * z - y * w), 2.0 * (y * z + x * w), 1.0 - 2.0 * (x * x + y * y)],
    ]
}
