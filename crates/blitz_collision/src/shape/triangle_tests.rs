//! 局所座標の三角形と、面の向きを備えた三角形の反証。面に垂直な変位の向きと長さ、面積が零の扱い、
//! 辺ごとの符号の3つを見る。
//!
//! 期待値は、水平な面に置いた直角三角形で書く。頂点を(0,0,0)・(4,0,0)・(0,0,4)に取ると、面に垂直な変位が
//! 天頂の軸に沿った長さ16の変位になり、面積8の2倍という関係が割り切れる十進の値で読める。
//!
//! 辺ごとの符号と内外の判定を面の向きを備えた三角形で見るのは、その判定が面に垂直な変位を必要とし、
//! 向きを添えた型だけがそれを求め直さずに持つためである。

use super::local_position::形の局所座標の位置;
use super::triangle::局所座標の三角形;
use super::triangle_vertex_number::三角形の頂点の番号;
use super::triangle_with_orientation::面の向きを備えた三角形;

fn 局所の点(成分: [f64; 3]) -> 形の局所座標の位置 {
    match 形の局所座標の位置::生成する(成分[0], 成分[1], 成分[2]) {
        Ok(位置) => 位置,
        Err(誤り) => panic!("試験用の局所の点を作れなかった: {誤り}"),
    }
}

fn 水平な直角三角形() -> 局所座標の三角形 {
    局所座標の三角形::三つの頂点から生成する([局所の点([0.0, 0.0, 0.0]), 局所の点([4.0, 0.0, 0.0]), 局所の点([0.0, 0.0, 4.0])])
}

fn 変位の成分(変位: super::local_displacement::形の局所座標の変位) -> [f64; 3] {
    [変位.xのメートル(), 変位.yのメートル(), 変位.zのメートル()]
}

fn 面の向きを備えた水平な直角三角形() -> 面の向きを備えた三角形 {
    match 面の向きを備えた三角形::三角形から生成する(水平な直角三角形()) {
        Some(三角形) => 三角形,
        None => panic!("試験用の三角形の面の向きを求められなかった"),
    }
}

#[test]
fn 辺の変位は番号の頂点から次の頂点へ向かう() {
    let 三角形 = 水平な直角三角形();
    assert_eq!(変位の成分(三角形.辺の変位を求める(三角形の頂点の番号::第1の頂点)), [4.0, 0.0, 0.0]);
    assert_eq!(変位の成分(三角形.辺の変位を求める(三角形の頂点の番号::第2の頂点)), [-4.0, 0.0, 4.0]);
    assert_eq!(変位の成分(三角形.辺の変位を求める(三角形の頂点の番号::第3の頂点)), [0.0, 0.0, -4.0]);
}

#[test]
fn 面に垂直な変位の長さは面積の2倍になる() {
    let 三角形 = 水平な直角三角形();
    assert_eq!(変位の成分(三角形.面に垂直な変位を求める()), [0.0, -16.0, 0.0]);
    assert_eq!(三角形.面に垂直な変位を求める().長さの二乗().sqrt(), 16.0);
    assert_eq!(三角形.面の単位法線の変位を求める().map(変位の成分), Some([0.0, -1.0, 0.0]));
}

#[test]
fn 一直線に並ぶ三点は面積が零で法線を持たない() {
    let 三角形 = 局所座標の三角形::三つの頂点から生成する(
        [局所の点([0.0, 0.0, 0.0]), 局所の点([1.0, 2.0, 3.0]), 局所の点([2.0, 4.0, 6.0])],
    );
    assert!(三角形.面積が零か());
    assert_eq!(三角形.面の単位法線の変位を求める().map(変位の成分), None);
}

#[test]
fn 辺の上の点は一つの符号だけが零になる() {
    let 三角形 = 面の向きを備えた水平な直角三角形();
    assert_eq!(三角形.辺ごとの符号を求める(局所の点([2.0, 0.0, 0.0])), [0.0, 128.0, 128.0]);
    assert!(三角形.面の上の点が内側にあるか(局所の点([2.0, 0.0, 0.0])));
}

#[test]
fn 頂点の上の点は二つの符号が零になる() {
    let 三角形 = 面の向きを備えた水平な直角三角形();
    assert_eq!(三角形.辺ごとの符号を求める(局所の点([4.0, 0.0, 0.0])), [0.0, 0.0, 256.0]);
}

#[test]
fn 三角形の外の点は内側と判定しない() {
    let 三角形 = 面の向きを備えた水平な直角三角形();
    assert!(三角形.面の上の点が内側にあるか(局所の点([1.0, 0.0, 1.0])));
    assert!(!三角形.面の上の点が内側にあるか(局所の点([3.0, 0.0, 3.0])));
}

#[test]
fn 面積が零の三角形は面の向きを備えた三角形を作れない() {
    let 三角形 = 局所座標の三角形::三つの頂点から生成する(
        [局所の点([0.0, 0.0, 0.0]), 局所の点([1.0, 2.0, 3.0]), 局所の点([2.0, 4.0, 6.0])],
    );
    assert!(面の向きを備えた三角形::三角形から生成する(三角形).is_none());
}
