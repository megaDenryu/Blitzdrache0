//! カプセル: 両端が半球になった円柱そのものである。軸の2つの端と半径だけを持ち、動きを持たない。
//!
//! 動きを添えた`形を掃引するカプセル`と別の型にするのは、問い合わせの相手として置かれるカプセルが形しか
//! 持たないためである。動くカプセルどうしの接触は片方を静止させた掃引へ写すため、静止させた側はこの型になる。
//! 掃引の側がこの型を保持して変位を添える形にしてあり、半径の検査の入口は2つに割れていない。
//!
//! 半径が正の有限でありその上限に収まることをこの型が守る。軸の両端は有限性と同じ上限を位置の型が守る。
//! 上限を課すのは、掃引の2次方程式の係数と判別式が桁あふれしないことを保証するためである。上限とその算術は
//! 形ごとの詳細判定が持つ。

use super::capsule_error::カプセルの生成エラー;
use super::coordinate_limit::形状の座標の絶対値の上限メートル;
use super::local_displacement::形の局所座標の変位;
use super::local_position::形の局所座標の位置;

/// 両端が半球になった円柱。軸の2つの端と、軸から測った半径で表す。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct カプセル {
    軸の始点: 形の局所座標の位置,
    軸の終点: 形の局所座標の位置,
    半径のメートル: f64,
}

impl カプセル {
    /// 半径が正の有限でありその上限に収まることを確かめて作る。軸の両端は同じ上限を位置の型が守る。
    pub fn 生成する(
        軸の始点: 形の局所座標の位置,
        軸の終点: 形の局所座標の位置,
        半径のメートル: f64,
    ) -> Result<Self, カプセルの生成エラー> {
        if !半径のメートル.is_finite() || 半径のメートル <= 0.0 {
            return Err(カプセルの生成エラー::カプセルの半径が正の有限値でない);
        }
        if 半径のメートル > f64::from(形状の座標の絶対値の上限メートル) {
            return Err(カプセルの生成エラー::カプセルの半径が上限を越えている);
        }
        Ok(Self {
            軸の始点,
            軸の終点,
            半径のメートル,
        })
    }

    /// 軸の始点。軸の上の比を0から1へ測る向きをこの端が決める。
    pub fn 軸の始点(&self) -> 形の局所座標の位置 {
        self.軸の始点
    }

    /// 軸の終点。
    pub fn 軸の終点(&self) -> 形の局所座標の位置 {
        self.軸の終点
    }

    /// 軸から測ったカプセルの半径であるメートル。
    pub fn 半径のメートル(&self) -> f64 {
        self.半径のメートル
    }

    // 軸の始点から終点へ向かう変位。長さ0の軸(球)も許すため、この変位は零になりうる。
    pub(crate) fn 軸の変位を求める(&self) -> 形の局所座標の変位 {
        self.軸の始点.終点までの変位を求める(self.軸の終点)
    }

    // 軸の2つの端点。並びは始点・終点であり、求解はこの順に候補を数える。
    pub(crate) fn 軸の端点を並べる(&self) -> [形の局所座標の位置; 2] {
        [self.軸の始点, self.軸の終点]
    }
}
