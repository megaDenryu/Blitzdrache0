//! 任意姿勢の直方体: 中心・回転・軸ごとの半分の長さで表す、姿勢の自由な直方体。
//!
//! 中心と回転が住むのは`ローカル`、すなわち据えた物が共有する群の原点(建物ではチャンクの基準原点)を原点とする
//! 空間である。個体配置と同じ空間で持つのは、建物の部品がその空間へ据えられた結果だからであり、大域の位置へ
//! 写すのは問い合わせを出す側の仕事である。
//!
//! 軸平行の箱にしないのは、向きを変えて据えた部品の箱が軸平行でなくなり、外接する軸平行の箱で近似すると実体より
//! 大きい形で当たりを返すためである。部品のローカル座標系で軸平行な箱は、倍率が同じ座標系の軸に沿って掛かるため、
//! 回転を掛ける前は必ず軸平行の直方体のままである。したがってこの表現は近似ではなく厳密である。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断5: 形状の目録を先に確定する(物理形状と描画形状は別物)」

use blitz_math::{クォータニオン, ローカル, 位置};

use super::coordinate_limit::形状の座標の絶対値の上限メートル;
use super::error::{直方体の生成エラー, 軸名一覧};
use super::half_extent::直方体の軸ごとの半分の長さ;

/// 中心・回転・軸ごとの半分の長さで表す、姿勢の自由な直方体。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 任意姿勢の直方体 {
    中心: 位置<ローカル>,
    回転: クォータニオン<ローカル, ローカル>,
    軸ごとの半分の長さ: 直方体の軸ごとの半分の長さ,
}

impl 任意姿勢の直方体 {
    /// 中心が有限であり形状の座標の上限に収まることを確かめてから受け入れる。回転は`クォータニオン`が正規化を
    /// 不変条件に持つため、ここでの検査は要らない。世界の側の範囲(チャンクの基準原点からの許容)はこの型が課さない。
    pub fn 生成する(
        中心: 位置<ローカル>,
        回転: クォータニオン<ローカル, ローカル>,
        軸ごとの半分の長さ: 直方体の軸ごとの半分の長さ,
    ) -> Result<Self, 直方体の生成エラー> {
        for (軸, 値) in 軸名一覧.into_iter().zip([中心.x(), 中心.y(), 中心.z()]) {
            if !値.値().is_finite() {
                return Err(直方体の生成エラー::中心が有限でない { 軸 });
            }
            if 値.値().abs() > 形状の座標の絶対値の上限メートル {
                return Err(直方体の生成エラー::中心が上限を越えている { 軸 });
            }
        }
        Ok(Self {
            中心,
            回転,
            軸ごとの半分の長さ,
        })
    }

    /// 群のローカル空間における直方体の中心。
    pub fn 中心(&self) -> 位置<ローカル> {
        self.中心
    }

    /// 直方体自身の軸を群のローカル空間の軸へ写す回転。
    pub fn 回転(&self) -> クォータニオン<ローカル, ローカル> {
        self.回転
    }

    /// 回転を掛ける前の、直方体自身の3軸に沿った半分の長さ。
    pub fn 軸ごとの半分の長さ(&self) -> 直方体の軸ごとの半分の長さ {
        self.軸ごとの半分の長さ
    }
}
