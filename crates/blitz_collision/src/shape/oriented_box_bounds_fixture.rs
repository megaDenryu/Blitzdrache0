//! 外接する箱の反証が共有する材料。直方体を組む道具と、箱の2つの端、および8つの角を単精度と倍精度のそれぞれで
//! 評価して並べる読み取りを持つ。
//!
//! 角を単精度の四元数の回転で組む側は、同じ幾何を単精度で評価し直す側(詳細判定)と同じ経路を通す。箱の合成は
//! 倍精度で行うが、包めていなければならない相手には単精度で評価された角も含まれる。
//!
//! 角を倍精度で組む側は、四元数の積で回す。合成の側が四元数から回転行列を組むのに対しこちらは積で回すため、
//! 同じ式を2度書いて突き合わせる形にならず、独立した拠り所になる。倍精度の角は幾何の真値の近似であり、箱が実体を
//! 包んでいるかはこちらで見る。

use blitz_math::{クォータニオン, メートル, ローカル, 位置, 変位};

use super::half_extent::直方体の軸ごとの半分の長さ;
use super::oriented_box::任意姿勢の直方体;

pub(super) fn 半分の長さを作る(成分: [f32; 3]) -> 直方体の軸ごとの半分の長さ {
    match 直方体の軸ごとの半分の長さ::生成する(成分.map(メートル::生成する)) {
        Ok(値) => 値,
        Err(誤り) => panic!("試験用の半分の長さを作れなかった: {誤り}"),
    }
}

pub(super) fn 直方体を作る(
    中心: [f32; 3], 回転: クォータニオン<ローカル, ローカル>, 半分: [f32; 3]
) -> 任意姿勢の直方体 {
    let 中心 = 位置::生成する(メートル::生成する(中心[0]), メートル::生成する(中心[1]), メートル::生成する(中心[2]));
    match 任意姿勢の直方体::生成する(中心, 回転, 半分の長さを作る(半分)) {
        Ok(直方体) => 直方体,
        Err(誤り) => panic!("試験用の直方体を作れなかった: {誤り}"),
    }
}

pub(super) fn 天頂まわりの4分の1回転() -> クォータニオン<ローカル, ローカル> {
    let 半角の正弦 = std::f32::consts::FRAC_1_SQRT_2;
    match クォータニオン::生成する(0.0, 半角の正弦, 0.0, 半角の正弦) {
        Ok(回転) => 回転,
        Err(誤り) => panic!("試験用の回転を作れなかった: {誤り}"),
    }
}

/// 外接する箱の最小の端と最大の端を、軸の順に並べた組で返す。
pub(super) fn 箱の2つの端を並べる(直方体: &任意姿勢の直方体) -> ([f32; 3], [f32; 3]) {
    let 箱 = 直方体.外接する軸平行の直方体を求める();
    (端の成分を並べる(箱.最小の端()), 端の成分を並べる(箱.最大の端()))
}

/// 直方体の8つの角を、単精度の回転で評価して並べる。番号のビットが軸ごとの符号を決める。
pub(super) fn 単精度で評価した8つの角を並べる(直方体: &任意姿勢の直方体) -> [[f32; 3]; 8] {
    let 半分 = [
        直方体.軸ごとの半分の長さ().x(),
        直方体.軸ごとの半分の長さ().y(),
        直方体.軸ごとの半分の長さ().z(),
    ];
    std::array::from_fn(|番号| {
        let 符号 = [0usize, 1, 2].map(|軸| if (番号 >> 軸) & 1 == 1 { 1.0_f32 } else { -1.0_f32 });
        let 角までの変位: 変位<ローカル> = 直方体
            .回転()
            .変位を回す(位置::<ローカル>::生成する(半分[0] * 符号[0], 半分[1] * 符号[1], 半分[2] * 符号[2]).原点からの変位());
        端の成分を並べる(直方体.中心().変位を足す(角までの変位))
    })
}

/// 直方体の8つの角を、四元数の積による倍精度の回転で評価して並べる。並びは単精度の側と同じ番号の順である。
pub(super) fn 倍精度で評価した8つの角を並べる(直方体: &任意姿勢の直方体) -> [[f64; 3]; 8] {
    let 中心 = [直方体.中心().x(), 直方体.中心().y(), 直方体.中心().z()].map(|成分| f64::from(成分.値()));
    let 半分 = [
        直方体.軸ごとの半分の長さ().x(),
        直方体.軸ごとの半分の長さ().y(),
        直方体.軸ごとの半分の長さ().z(),
    ]
    .map(|長さ| f64::from(長さ.値()));
    let 単位四元数 = 倍精度で正規化した四元数(直方体);
    std::array::from_fn(|番号| {
        let 符号 = [0usize, 1, 2].map(|軸| if (番号 >> 軸) & 1 == 1 { 1.0_f64 } else { -1.0_f64 });
        let 回した角 = 四元数で回す(単位四元数, [0usize, 1, 2].map(|軸| 半分[軸] * 符号[軸]));
        [0usize, 1, 2].map(|軸| 中心[軸] + 回した角[軸])
    })
}

fn 倍精度で正規化した四元数(直方体: &任意姿勢の直方体) -> [f64; 4] {
    let 成分 = 直方体.回転().境界用xyzw配列().map(f64::from);
    let 長さ = (成分[0] * 成分[0] + 成分[1] * 成分[1] + 成分[2] * 成分[2] + 成分[3] * 成分[3]).sqrt();
    成分.map(|値| 値 / 長さ)
}

// 四元数の積を2回取って回す。並びはx・y・z・wであり、逆回転は虚部の符号を反転したものである。
fn 四元数で回す(単位四元数: [f64; 4], 変位: [f64; 3]) -> [f64; 3] {
    let [x, y, z, w] = 単位四元数;
    let 逆回転 = [-x, -y, -z, w];
    let 積 = 四元数の積(四元数の積(単位四元数, [変位[0], 変位[1], 変位[2], 0.0]), 逆回転);
    [積[0], 積[1], 積[2]]
}

fn 四元数の積(左: [f64; 4], 右: [f64; 4]) -> [f64; 4] {
    let ([左x, 左y, 左z, 左w], [右x, 右y, 右z, 右w]) = (左, 右);
    [
        左w * 右x + 左x * 右w + 左y * 右z - 左z * 右y,
        左w * 右y - 左x * 右z + 左y * 右w + 左z * 右x,
        左w * 右z + 左x * 右y - 左y * 右x + 左z * 右w,
        左w * 右w - 左x * 右x - 左y * 右y - 左z * 右z,
    ]
}

fn 端の成分を並べる(端: 位置<ローカル>) -> [f32; 3] {
    [端.x().値(), 端.y().値(), 端.z().値()]
}
