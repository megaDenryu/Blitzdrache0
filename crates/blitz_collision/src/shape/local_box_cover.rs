//! 局所座標の箱から、問い合わせが触れうる範囲の覆いを組む工程。受け取るのは広げる長さと掃く変位、返すのは
//! 覆いの箱である。触れるのは自分の2つの端だけである。
//!
//! 箱の代数(`crates/blitz_collision/src/shape/local_axis_aligned_box.rs`)と別のファイルへ置くのは、こちらが
//! 問い合わせの覆いを組む局面であり、丸めを外から包む幅を足す唯一の場所だからである。箱そのものの操作
//! (2点への外接・畳み込み・重なり)は最小と最大を選ぶだけで丸めを通さない。
//!
//! 幅の導出は`crates/blitz_collision/src/shape/cover_rounding_margin.rs`が持つものをそのまま使う。導出は
//! 広げる長さと掃く変位の成分が丸めを通らない値であることを前提にするが、ここではどちらも呼び出し側が渡した
//! 倍精度の値そのものであるから前提は満たされている。幅を足す理由も同じであり、覆いの端が内側へ入ると、覆いに
//! 真に触れている三角形を階層の走査が候補から落とし、当たりが在るのに無いと答える。この誤りは詳細判定でも
//! 取り返せない。外へ広げすぎる側の害は、触れない三角形を数件余計に詳細判定へ渡すことだけである。

use super::cover_rounding_margin::{
    全方向へ広げた端が受ける丸めを包む幅を求める, 掃いた端が受ける丸めを包む幅を求める
};
use super::local_axis_aligned_box::局所座標の軸平行の直方体;
use super::local_displacement::形の局所座標の変位;

impl 局所座標の軸平行の直方体 {
    /// 全方向へ同じ長さだけ広げた箱。掃引するカプセルの覆いは、軸の両端に外接する箱を半径ぶん広げて作る。
    ///
    /// 前提: 長さが0以上の有限値であること。負の長さを渡すと箱が裏返り、最小の端が最大の端を越える。
    pub fn 全方向へ広げた箱を求める(&self, 長さのメートル: f64) -> Self {
        let (最小, 最大) = self.軸の順に並べた両端を読む();
        let 丸めを包む幅 = 全方向へ広げた端が受ける丸めを包む幅を求める(最小, 最大, 長さのメートル);
        Self::軸の順に並べた両端から組む(
            [0usize, 1, 2].map(|軸| 最小[軸] - 長さのメートル),
            [0usize, 1, 2].map(|軸| 最大[軸] + 長さのメートル),
        )
        .軸ごとの幅だけ端を外へ広げた箱を求める(丸めを包む幅)
    }

    /// 変位のぶんだけ平行移動させて掃いた範囲を包む箱。掃引の覆いは、広げた箱からこれで作る。
    pub fn 変位で掃いた箱を求める(&self, 変位: 形の局所座標の変位) -> Self {
        let (最小, 最大) = self.軸の順に並べた両端を読む();
        let 移動 = [変位.xのメートル(), 変位.yのメートル(), 変位.zのメートル()];
        let 丸めを包む幅 = 掃いた端が受ける丸めを包む幅を求める(最小, 最大, 移動);
        Self::軸の順に並べた両端から組む(
            [0usize, 1, 2].map(|軸| 最小[軸].min(最小[軸] + 移動[軸])),
            [0usize, 1, 2].map(|軸| 最大[軸].max(最大[軸] + 移動[軸])),
        )
        .軸ごとの幅だけ端を外へ広げた箱を求める(丸めを包む幅)
    }

    // 軸ごとの幅だけ端を外側へ広げた箱。端を組む計算の丸めを包むためにだけ使う。
    fn 軸ごとの幅だけ端を外へ広げた箱を求める(&self, 幅: [f64; 3]) -> Self {
        let (最小, 最大) = self.軸の順に並べた両端を読む();
        Self::軸の順に並べた両端から組む([0usize, 1, 2].map(|軸| 最小[軸] - 幅[軸]), [0usize, 1, 2].map(|軸| 最大[軸] + 幅[軸]))
    }
}
