//! 形の局所座標の軸: 形が共有する局所座標系の3本の軸のどれかである。並びは位置と変位の成分と同じx・y・zであり、
//! 1本の軸を選んだあとに残る2本を並びの順で言うための巡回の順を持つ。
//!
//! `直方体自身の座標軸`と別の型にするのは、あちらが回転を掛ける前の直方体が自分で持つ軸であり、直方体を回すと
//! 局所座標系のどの軸とも一致しなくなるためである。こちらは局所座標系そのものの軸であり、どの形にも属さない。
//!
//! 使うのは、線分の向きの成分がいちばん大きい軸を選び、残る2本を写す面の横と縦に取る剪断である。
//! 参照: `crates/blitz_collision/src/triangle/segment_shear_frame.rs`

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 形の局所座標の軸 {
    X軸,
    Y軸,
    Z軸,
}

impl 形の局所座標の軸 {
    // 巡回の順で次に来る軸。x軸の次はy軸、y軸の次はz軸、z軸の次はx軸である。
    pub(crate) fn 次の軸(self) -> Self {
        match self {
            Self::X軸 => Self::Y軸,
            Self::Y軸 => Self::Z軸,
            Self::Z軸 => Self::X軸,
        }
    }
}
