//! 外接する軸平行の直方体の合成の反証。
//!
//! 見るのは3つである。回転が恒等なら箱が中心と半分の長さそのものになること、天頂まわりの4分の1回転で東西と南北の
//! 広がりが入れ替わること、そして任意の回転でも直方体の8つの角が必ず箱の中に入ることである。3つ目が本体であり、
//! 前の2つはその値が正しい向きに出ていることを人が読める形で押さえる。

use blitz_math::{クォータニオン, ローカル, メートル, 位置, 変位};

use super::half_extent::直方体の軸ごとの半分の長さ;
use super::oriented_box::任意姿勢の直方体;

// 端の余白は座標の大きさの2の16乗分の1であり、この試験が使う座標(絶対値5メートル以下)では1万分の1メートルに
// 満たない。合わせて回転の適用の丸めも入るため、包含の下限と締まりの上限をこの幅で見る。
const 許容メートル: f32 = 1.0e-3;

fn 半分の長さを作る(成分: [f32; 3]) -> 直方体の軸ごとの半分の長さ {
    match 直方体の軸ごとの半分の長さ::生成する(成分.map(メートル::生成する)) {
        Ok(値) => 値,
        Err(誤り) => panic!("試験用の半分の長さを作れなかった: {誤り}"),
    }
}

fn 直方体を作る(中心: [f32; 3], 回転: クォータニオン<ローカル, ローカル>, 半分: [f32; 3]) -> 任意姿勢の直方体 {
    let 中心 = 位置::生成する(メートル::生成する(中心[0]), メートル::生成する(中心[1]), メートル::生成する(中心[2]));
    match 任意姿勢の直方体::生成する(中心, 回転, 半分の長さを作る(半分)) {
        Ok(直方体) => 直方体,
        Err(誤り) => panic!("試験用の直方体を作れなかった: {誤り}"),
    }
}

fn 天頂まわりの4分の1回転() -> クォータニオン<ローカル, ローカル> {
    let 半角の正弦 = std::f32::consts::FRAC_1_SQRT_2;
    match クォータニオン::生成する(0.0, 半角の正弦, 0.0, 半角の正弦) {
        Ok(回転) => 回転,
        Err(誤り) => panic!("試験用の回転を作れなかった: {誤り}"),
    }
}

fn 端の成分を並べる(端: 位置<ローカル>) -> [f32; 3] {
    [端.x().値(), 端.y().値(), 端.z().値()]
}

// 箱が中心±広がりを包み、かつ許容の幅を越えて広がっていないことを軸ごとに見る。
fn 中心と広がりに合うことを確かめる(直方体: &任意姿勢の直方体, 中心: [f32; 3], 広がり: [f32; 3]) {
    let 箱 = 直方体.外接する軸平行の直方体を求める();
    let 最小 = 端の成分を並べる(箱.最小の端());
    let 最大 = 端の成分を並べる(箱.最大の端());
    for 軸 in 0usize..3 {
        assert!(最小[軸] <= 中心[軸] - 広がり[軸], "軸{軸}の最小が実体を包んでいない");
        assert!(最小[軸] >= 中心[軸] - 広がり[軸] - 許容メートル, "軸{軸}の最小が広すぎる");
        assert!(最大[軸] >= 中心[軸] + 広がり[軸], "軸{軸}の最大が実体を包んでいない");
        assert!(最大[軸] <= 中心[軸] + 広がり[軸] + 許容メートル, "軸{軸}の最大が広すぎる");
    }
}

#[test]
fn 回転が恒等なら箱は中心と半分の長さそのものになる() {
    let 直方体 = 直方体を作る([1.0, 2.5, -3.5], クォータニオン::恒等(), [1.5, 1.25, 0.25]);
    中心と広がりに合うことを確かめる(&直方体, [1.0, 2.5, -3.5], [1.5, 1.25, 0.25]);
}

#[test]
fn 天頂まわりの4分の1回転で東西と南北の広がりが入れ替わる() {
    let 直方体 = 直方体を作る([1.0, 2.5, -3.5], 天頂まわりの4分の1回転(), [1.5, 1.25, 0.25]);
    中心と広がりに合うことを確かめる(&直方体, [1.0, 2.5, -3.5], [0.25, 1.25, 1.5]);
}

#[test]
fn どの回転でも8つの角が箱の中に入る() {
    let 回転 = match クォータニオン::<ローカル, ローカル>::生成する(0.35, -0.62, 0.18, 0.68) {
        Ok(回転) => 回転,
        Err(誤り) => panic!("試験用の回転を作れなかった: {誤り}"),
    };
    let 直方体 = 直方体を作る([-2.0, 0.75, 4.25], 回転, [1.5, 1.25, 0.25]);
    let 箱 = 直方体.外接する軸平行の直方体を求める();
    let 最小 = 端の成分を並べる(箱.最小の端());
    let 最大 = 端の成分を並べる(箱.最大の端());
    let 半分 = [直方体.軸ごとの半分の長さ().x(), 直方体.軸ごとの半分の長さ().y(), 直方体.軸ごとの半分の長さ().z()];
    for 番号 in 0u32..8 {
        let 符号 = [0usize, 1, 2].map(|軸| if (番号 >> 軸) & 1 == 1 { 1.0_f32 } else { -1.0_f32 });
        let 角までの変位: 変位<ローカル> = 直方体.回転().変位を回す(
            位置::<ローカル>::生成する(半分[0] * 符号[0], 半分[1] * 符号[1], 半分[2] * 符号[2]).原点からの変位(),
        );
        let 角 = 端の成分を並べる(直方体.中心().変位を足す(角までの変位));
        for 軸 in 0usize..3 {
            assert!(最小[軸] <= 角[軸] && 角[軸] <= 最大[軸], "角{番号}の軸{軸}が箱の外にある");
        }
    }
}
