//! 直方体の面の向き: 1本の軸に垂直な2つの面のうち、軸の正の側か負の側かである。
//!
//! 真偽値で持たないのは、真がどちらの側を指すかを呼び出し側が別の決まりで覚えることになるためである。
//! 面・辺・頂点のどれもこの向きを使う。面は1本の軸の向き、辺は2本の軸の向き、頂点は3本の軸の向きで決まる。

/// 1本の軸に垂直な2つの面のうちのどちらか。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum 直方体の面の向き {
    /// 軸の正の向きへ半分の長さだけ進んだ側の面。
    軸の正の側,
    /// 軸の負の向きへ半分の長さだけ進んだ側の面。
    軸の負の側,
}

impl 直方体の面の向き {
    /// 2つの向きを、求解が候補を数える順に並べる。
    pub fn 並べる() -> [Self; 2] {
        [Self::軸の正の側, Self::軸の負の側]
    }

    /// 中心から面へ向かうときに半分の長さへ掛ける符号。
    pub fn 符号(self) -> f64 {
        match self {
            Self::軸の正の側 => 1.0,
            Self::軸の負の側 => -1.0,
        }
    }

    /// 同じ軸に垂直なもう一方の面の側。板の中に居る時刻の区間では、入る側の反対が出る側である。
    pub fn 反対の側(self) -> Self {
        match self {
            Self::軸の正の側 => Self::軸の負の側,
            Self::軸の負の側 => Self::軸の正の側,
        }
    }

    /// 実数の符号が指す側。零は正の側として扱う。中心のちょうど上に在る点がどちらの面に近いかは
    /// 決まらないため、並びの先に来る側を選んで答えを入力だけで決める。
    pub fn 実数の符号が指す側を求める(値: f64) -> Self {
        if 値 < 0.0 { Self::軸の負の側 } else { Self::軸の正の側 }
    }
}
