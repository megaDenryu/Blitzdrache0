//! 面の向きを備えた三角形: 3つの頂点の位置に、その並びから導いた面の向きを添えたものである。詳細判定が
//! 相手にする三角形はこの形であり、面の向きを使う判定(平面までの隔たり・辺ごとの符号・面の上の点の内外)を
//! この型が持つ。
//!
//! 三角形と面の向きを1つにまとめるのは、面の向きが三角形から導いた量であり、別々に持ち回すと別の三角形から
//! 求めた向きを渡しても型が通るためである。問い合わせは生成の1回でこの型を組み、以後は外積も平方根も通らない。
//!
//! 面積が零の三角形はこの型を作れない。面の向きが定まらないためである。拒む地点をここに置くことで、判定の側は
//! 向きが定まっていることを前提にできる。

use super::local_displacement::形の局所座標の変位;
use super::local_position::形の局所座標の位置;
use super::triangle::局所座標の三角形;
use super::triangle_face_orientation::三角形の面の向き;
use super::triangle_vertex_number::三角形の頂点の番号;

/// 3つの頂点の位置に、その並びから導いた面の向きを添えた三角形。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 面の向きを備えた三角形 {
    三角形: 局所座標の三角形,
    面の向き: 三角形の面の向き,
}

impl 面の向きを備えた三角形 {
    /// 三角形から面の向きを求めて組む。面積が零で向きが定まらない三角形では値なしを返す。
    pub fn 三角形から生成する(三角形: 局所座標の三角形) -> Option<Self> {
        let 面の向き = 三角形の面の向き::三角形から求める(&三角形)?;
        Some(Self { 三角形, 面の向き })
    }

    /// 別に求めておいた面の向きを添えて組む。三角形網が三角形ごとの面の向きを保持し、候補1枚ごとに外積と
    /// 平方根を通し直さないための入口である。
    ///
    /// 前提: 面の向きがこの三角形から求めたものであること。別の三角形の向きを渡すと、内外の判定も接触の
    /// 単位法線も別の面のものになる。
    pub fn 面の向きを添えて生成する(三角形: 局所座標の三角形, 面の向き: 三角形の面の向き) -> Self {
        Self { 三角形, 面の向き }
    }

    /// 面の向きを外した、3つの頂点の位置だけの三角形。
    pub fn 三角形(&self) -> &局所座標の三角形 {
        &self.三角形
    }

    /// 添えている面の向き。三角形網が三角形1枚ごとにこれだけを保持し、頂点は頂点の列から番号で引く。
    pub fn 面の向き(&self) -> 三角形の面の向き {
        self.面の向き
    }

    /// 番号が指す頂点の位置。
    pub fn 頂点の位置(&self, 番号: 三角形の頂点の番号) -> 形の局所座標の位置 {
        self.三角形.頂点の位置(番号)
    }

    /// 番号の頂点から次の番号の頂点へ向かう変位。3つの番号でこの三角形の3辺が尽きる。
    pub fn 辺の変位を求める(&self, 始まりの頂点: 三角形の頂点の番号) -> 形の局所座標の変位 {
        self.三角形.辺の変位を求める(始まりの頂点)
    }

    /// 長さを1に正していない、面に垂直な変位。長さは三角形の面積の2倍である。
    pub fn 面に垂直な変位(&self) -> 形の局所座標の変位 {
        self.面の向き.面に垂直な変位()
    }

    /// 面に垂直な変位を長さ1に正したもの。
    pub fn 単位法線の変位(&self) -> 形の局所座標の変位 {
        self.面の向き.単位法線の変位()
    }
}
