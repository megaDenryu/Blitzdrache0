//! 局所座標の軸平行の直方体の反証。外接・畳み込み・重なり・最も長い軸と、覆いを組む2つの操作を見る。
//!
//! 外接と畳み込みは最小と最大を選ぶだけで丸めを通さないため、値の一致で書ける。覆いを組む操作は丸めを外から
//! 包む幅だけ端が外へ出るため、期待の箱を含むことと、外への出方が幅の桁に収まることで書く。

use super::box_axis::直方体自身の座標軸;
use super::local_axis_aligned_box::局所座標の軸平行の直方体;
use super::local_displacement::形の局所座標の変位;
use super::local_position::形の局所座標の位置;

// 覆いの端が外へ出る幅の上限。端の絶対値の和の2の49乗分の1であり、この反証の大きさ(十メートルの桁まで)では
// 1兆分の1メートルに遠く届かない。
// 参照: `crates/blitz_collision/src/shape/cover_rounding_margin.rs`
const 丸めを包む幅の上限メートル: f64 = 1e-12;

fn 局所の点(成分: [f64; 3]) -> 形の局所座標の位置 {
    match 形の局所座標の位置::生成する(成分[0], 成分[1], 成分[2]) {
        Ok(位置) => 位置,
        Err(誤り) => panic!("試験用の局所の点を作れなかった: {誤り}"),
    }
}

fn 箱を作る(最小: [f64; 3], 最大: [f64; 3]) -> 局所座標の軸平行の直方体 {
    局所座標の軸平行の直方体::二点に外接する箱を求める(局所の点(最小), 局所の点(最大))
}

fn 位置の成分(位置: 形の局所座標の位置) -> [f64; 3] {
    [位置.xのメートル(), 位置.yのメートル(), 位置.zのメートル()]
}

fn 期待の箱を丸めの幅のぶんだけ外から包むことを確かめる(
    覆い: &局所座標の軸平行の直方体,
    期待の最小: [f64; 3],
    期待の最大: [f64; 3],
) {
    let 許す範囲 = 0.0..丸めを包む幅の上限メートル;
    let 最小 = 位置の成分(覆い.最小の端());
    let 最大 = 位置の成分(覆い.最大の端());
    for 軸 in 0usize..3 {
        assert!(許す範囲.contains(&(期待の最小[軸] - 最小[軸])), "最小の端のはみ出しが許す範囲の外にある");
        assert!(許す範囲.contains(&(最大[軸] - 期待の最大[軸])), "最大の端のはみ出しが許す範囲の外にある");
    }
}

#[test]
fn 三点に外接する箱は成分ごとの最小と最大になる() {
    let 箱 = 局所座標の軸平行の直方体::三点に外接する箱を求める(
        [局所の点([1.0, 5.0, -2.0]), 局所の点([-3.0, 2.0, 4.0]), 局所の点([0.0, 9.0, 1.0])],
    );
    assert_eq!(位置の成分(箱.最小の端()), [-3.0, 2.0, -2.0]);
    assert_eq!(位置の成分(箱.最大の端()), [1.0, 9.0, 4.0]);
}

#[test]
fn 二つの箱を畳むと両方を包む箱になる() {
    let 畳んだ = 箱を作る([0.0, 0.0, 0.0], [1.0, 1.0, 1.0]).相手を含む箱を求める(&箱を作る([-2.0, 0.5, 0.25], [0.5, 3.0, 0.75]));
    assert_eq!(位置の成分(畳んだ.最小の端()), [-2.0, 0.0, 0.0]);
    assert_eq!(位置の成分(畳んだ.最大の端()), [1.0, 3.0, 1.0]);
}

#[test]
fn 境界で触れるだけの箱も交わりとして数える() {
    let 一方 = 箱を作る([0.0, 0.0, 0.0], [1.0, 1.0, 1.0]);
    assert!(一方.相手と交わるか(&箱を作る([1.0, 0.0, 0.0], [2.0, 1.0, 1.0])));
    assert!(!一方.相手と交わるか(&箱を作る([1.5, 0.0, 0.0], [2.0, 1.0, 1.0])));
}

#[test]
fn 最も長い軸は長さが並んだとき並びの先の軸になる() {
    assert_eq!(箱を作る([0.0, 0.0, 0.0], [1.0, 3.0, 2.0]).最も長い軸を求める(), 直方体自身の座標軸::Y軸);
    assert_eq!(箱を作る([0.0, 0.0, 0.0], [2.0, 2.0, 2.0]).最も長い軸を求める(), 直方体自身の座標軸::X軸);
    assert_eq!(箱を作る([0.0, 0.0, 0.0], [1.0, 2.0, 2.0]).最も長い軸を求める(), 直方体自身の座標軸::Y軸);
}

#[test]
fn 覆いは半径ぶん広げてから変位ぶん掃いた範囲を包む() {
    let 覆い = 箱を作る([0.0, 0.0, 0.0], [0.0, 2.0, 0.0])
        .全方向へ広げた箱を求める(0.5)
        .変位で掃いた箱を求める(match 形の局所座標の変位::生成する(3.0, 0.0, -1.0) {
            Ok(変位) => 変位,
            Err(誤り) => panic!("試験用の変位を作れなかった: {誤り}"),
        });
    期待の箱を丸めの幅のぶんだけ外から包むことを確かめる(&覆い, [-0.5, -0.5, -1.5], [3.5, 2.5, 0.5]);
}
