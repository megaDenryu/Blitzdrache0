//! 形状の座標が守る絶対値の上限と、外接する箱の端へ足す余白の相対量。
//!
//! 上限を課すのは、任意姿勢の直方体から外接する軸平行の直方体を合成する計算が、途中でも結果でも単精度の
//! 表せる範囲を出ないことを保証するためである。合成は「中心 ± 回転で写した軸ごとの広がりの和 ± 余白」であり、
//! 回転は長さを変えないから広がりの各成分は軸ごとの半分の長さ以下、その3軸の和は上限の3倍以下である。余白は
//! 下に書くとおり中心と半分の長さの総和の2の16乗分の1以下、すなわち上限の4倍の2の16乗分の1以下である。
//! したがって箱の端は上限の4倍をわずかに越える程度、すなわち2の26乗メートルを少し越えたところに収まり、
//! 単精度の最大値(およそ3.4かける10の38乗)を大きく下回る。上限が無ければ、有限な中心と有限な半分の長さの組から
//! 有限でない端が出て、選別が黙って何とも交わらない箱を作る。
//!
//! 値が高さ場の問い合わせの上限(`crates/blitz_collision/src/height_field/length_limit.rs`)と同じ2の24乗
//! メートルであるのは、どちらも同じ世界の座標に課す上限であり、値が食い違うと同じ位置が片方の問い合わせでだけ
//! 拒まれるためである。根拠は別である(高さ場の側は掃引の2次方程式の判別式が桁あふれしないこと)。
//!
//! 余白は、箱が実体より小さく出ることを防ぐために端の外側へ足す幅である。基準を「回転で写した広がり」ではなく
//! 「中心の絶対値と軸ごとの半分の長さの総和」に取るのは、丸めの絶対誤差が半分の長さに比例し、広がりには比例
//! しないためである。長い半軸がほぼ直交へ回った箱では、真の広がりが半分の長さの何万分の1になっても、その広がりを
//! 評価したときの誤差は半分の長さに比例したまま残る。小さく出た結果自身に比例する余白では包めない。
//!
//! 幅が包むべき誤差は2つあり、実装順6で詳細判定を書いた時点で、どちらも実際の演算列から数え直した。合成の側と
//! 詳細判定の側が同じ`oriented_box_double.rs`の読み直しを通るため、2つの誤差は同じ項から育つ。以下では中心の
//! 絶対値と軸ごとの半分の長さの総和の合計をSと書き、倍精度の演算1回の相対誤差の上限2の53乗分の1をuと書く。
//!
//! 共通の項は直方体自身の軸の成分である。四元数の長さは二乗4回と加算3回と平方根1回であるから相対誤差は4.5u以下、
//! 長さで割った4成分はそれぞれ5.5u以下である。回転行列の成分は2つの積とその和(または差)であるから、絶対値が
//! 1以下の成分に対する絶対誤差は27u以下になる。
//!
//! 合成の側は、軸の成分の絶対値と半分の長さの積を3つ足して広がりを作り、中心へ足し引きして余白を足す。積の丸めが
//! 半分の長さの28u倍以下、加算の丸めが半分の長さの総和の2u倍以下、中心との足し引きと余白の加算がSの2u倍以下で
//! あるから、合わせて32u·S以下である。
//!
//! 詳細判定の側は、すべての算術を倍精度で行う。単精度へ狭めるのは接触の単位法線を返す1箇所だけであり、位置は
//! 倍精度のまま返る。導く点のうち演算が最も多いのは直方体の角であり、軸へ半分の長さを掛けて3つ足し中心へ足す。
//! 積の丸めが半分の長さの28u倍以下、和の丸めが3回でSの3u倍以下であるから、合わせて31u·S以下である。面の中央と
//! 辺の始点は角より演算が少なく、この上界に収まる。
//!
//! したがってどちらの誤差もSの2の48乗分の1以下であり、余白の相対量2の16乗分の1はその40億倍以上である。旧版は
//! 詳細判定の側を「単精度で角や面を組み直す」という前提で見積もり、単精度の刻みを使ってSの6倍程度としていた。
//! 実装した詳細判定は倍精度であるうえ軸の読み直しを合成と共有するため、実際の誤差はその見積もりより10の7乗倍
//! 以上小さい。合成の側の旧版の数値(Sの2の49乗分の1)は回転行列の成分の誤差を数え落としていたため、上の32u·Sへ
//! 改めた。どちらの向きに直しても余白が包むという結論は変わらない。
//! 参照: `crates/blitz_collision/src/oriented_box.rs`
//!
//! 端を単精度へ戻すときの丸めは外向きに固定する(`crates/blitz_collision/src/shape/outward_narrowing.rs`)。
//! 最近接へ丸めると、余白を足した端が単精度の1刻みぶん内側へ戻りうるためである。

/// 形状の座標(任意姿勢の直方体の中心と軸ごとの半分の長さ)が守る絶対値の上限であるメートル。2の24乗である。
pub const 形状の座標の絶対値の上限メートル: f32 = 16_777_216.0;

// 外接する箱の端を外側へ広げる幅の、中心の絶対値と半分の長さの総和の合計に対する比。2の16乗分の1である。
pub(super) const 外接する箱の余白の相対量: f32 = 1.0 / 65_536.0;
