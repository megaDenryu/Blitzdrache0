//! 形状の座標が守る絶対値の上限と、外接する箱の端へ足す余白の相対量。
//!
//! 上限を課すのは、任意姿勢の直方体から外接する軸平行の直方体を合成する計算が、途中でも結果でも単精度の
//! 表せる範囲を出ないことを保証するためである。合成は「中心 ± 回転で写した軸ごとの広がりの和」であり、
//! 回転は長さを変えないから広がりの各成分は軸ごとの半分の長さ以下、その3軸の和は上限の3倍以下である。
//! したがって箱の端は上限の4倍すなわち2の26乗メートル以下であり、単精度の最大値(およそ3.4かける10の38乗)を
//! 大きく下回る。上限が無ければ、有限な中心と有限な半分の長さの組から有限でない端が出て、選別が黙って
//! 何とも交わらない箱を作る。
//!
//! 値が高さ場の問い合わせの上限(`crates/blitz_collision/src/height_field/length_limit.rs`)と同じ2の24乗
//! メートルであるのは、どちらも同じ世界の座標に課す上限であり、値が食い違うと同じ位置が片方の問い合わせでだけ
//! 拒まれるためである。根拠は別である(高さ場の側は掃引の2次方程式の判別式が桁あふれしないこと)。
//!
//! 余白は、合成の丸めで箱が実体より小さく出ることを防ぐために端の外側へ足す幅である。回転を変位へ適用する
//! 計算は外部の四元数の実装が行うため、その丸めの厳密な上界をここで導けない。導けない量を無視すると、
//! 直方体の面のちょうど上を通る問い合わせを選別が落としうる。落とす側の誤りは詳細判定で取り返せないのに対し、
//! 広く取る側の誤りは詳細判定が候補を1件余計に捨てるだけであるから、単精度の刻み(2の23乗分の1)の128倍という、
//! 積み重なりうる丸めを大きく上回る幅を座標の大きさに比例させて取る。

/// 形状の座標(任意姿勢の直方体の中心と軸ごとの半分の長さ)が守る絶対値の上限であるメートル。2の24乗である。
pub const 形状の座標の絶対値の上限メートル: f32 = 16_777_216.0;

// 外接する箱の端を外側へ広げる幅の、座標の大きさに対する比。2の16乗分の1である。
pub(super) const 外接する箱の余白の相対量: f32 = 1.0 / 65_536.0;
