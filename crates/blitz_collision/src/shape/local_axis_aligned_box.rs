//! 局所座標の軸平行の直方体: 形が共有する1つの局所座標系で、座標軸に平行な面だけを持つ倍精度の直方体である。
//!
//! 単精度の`軸平行の直方体`と別の型にするのは、こちらが形の内側の空間索引で使われるためである。三角形網の階層は
//! 節点の境界を頂点の位置そのものの最小と最大で組む。最小と最大を選ぶ操作は丸めを1つも通さないため、節点の境界が
//! 配下の三角形を厳密に包むことを演算の性質だけで言える。端を単精度へ狭めると、そこで初めて丸めが入り、外向きへ
//! 広げる余白が要る。倍精度のまま持てば余白そのものが要らない。
//!
//! 大域の軸平行の直方体と別の型にするのは、端の住む座標系が違うためである。あちらは世界の原点を基準にした端を
//! 持ち、チャンクの境界と突き合わせる。こちらは形の局所座標系の端を持ち、同じ形の中の三角形と突き合わせる。
//!
//! 軸を`直方体自身の座標軸`で指すのは、軸平行の箱では直方体自身の軸が局所座標系の軸とそのまま重なるためである。
//! 局所座標系の軸を指す型を別に作ると、同じ1つの概念が2つの綴りになる。

use super::box_axis::直方体自身の座標軸;
use super::local_position::形の局所座標の位置;

/// 形が共有する局所座標系で、座標軸に平行な面だけを持つ倍精度の直方体。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 局所座標の軸平行の直方体 {
    最小の端: [f64; 3],
    最大の端: [f64; 3],
}

impl 局所座標の軸平行の直方体 {
    /// 2つの位置に外接する箱。成分の大小を選ぶだけで丸めを1つも通さない。
    pub fn 二点に外接する箱を求める(端: 形の局所座標の位置, もう一方の端: 形の局所座標の位置) -> Self {
        let 一方 = 成分を軸の順に並べる(端);
        let 他方 = 成分を軸の順に並べる(もう一方の端);
        Self {
            最小の端: [0usize, 1, 2].map(|軸| 一方[軸].min(他方[軸])),
            最大の端: [0usize, 1, 2].map(|軸| 一方[軸].max(他方[軸])),
        }
    }

    /// 3つの位置に外接する箱。三角形1つを包む境界はこれで作る。丸めを1つも通さない。
    pub fn 三点に外接する箱を求める(点: [形の局所座標の位置; 3]) -> Self {
        Self::二点に外接する箱を求める(点[0], 点[1]).相手を含む箱を求める(&Self::二点に外接する箱を求める(点[2], 点[2]))
    }

    /// 自分と相手の両方を包む箱。階層の節点の境界は、子の箱をこの操作で畳んで作る。丸めを1つも通さない。
    pub fn 相手を含む箱を求める(&self, 相手: &Self) -> Self {
        Self {
            最小の端: [0usize, 1, 2].map(|軸| self.最小の端[軸].min(相手.最小の端[軸])),
            最大の端: [0usize, 1, 2].map(|軸| self.最大の端[軸].max(相手.最大の端[軸])),
        }
    }

    /// 自分と相手が3軸すべてで重なるか。境界で触れるだけの場合も重なりとして数える。触れている形を落とさないためである。
    pub fn 相手と交わるか(&self, 相手: &Self) -> bool {
        (0usize..3).all(|軸| self.最小の端[軸] <= 相手.最大の端[軸] && 相手.最小の端[軸] <= self.最大の端[軸])
    }

    /// 成分ごとに小さいほうを集めた端。
    pub fn 最小の端(&self) -> 形の局所座標の位置 {
        形の局所座標の位置::検査済みの成分から組む(self.最小の端[0], self.最小の端[1], self.最小の端[2])
    }

    /// 成分ごとに大きいほうを集めた端。
    pub fn 最大の端(&self) -> 形の局所座標の位置 {
        形の局所座標の位置::検査済みの成分から組む(self.最大の端[0], self.最大の端[1], self.最大の端[2])
    }

    /// 1本の軸に沿った、最小の端から最大の端までの長さであるメートル。
    pub fn 軸に沿った長さのメートル(&self, 軸: 直方体自身の座標軸) -> f64 {
        self.最大の端[軸.並びの位置()] - self.最小の端[軸.並びの位置()]
    }

    /// 1本の軸に沿った、2つの端のちょうど真ん中であるメートル。階層の分割はこの値の中央で三角形を2つに分ける。
    pub fn 軸に沿った中央のメートル(&self, 軸: 直方体自身の座標軸) -> f64 {
        0.5 * (self.最小の端[軸.並びの位置()] + self.最大の端[軸.並びの位置()])
    }

    /// 3軸のうち最も長い軸。長さが並んだときは軸の並びの先に来る軸を返し、答えを入力だけで決める。
    pub fn 最も長い軸を求める(&self) -> 直方体自身の座標軸 {
        直方体自身の座標軸::並べる().into_iter().fold(直方体自身の座標軸::X軸, |最長, 軸| {
            if self.軸に沿った長さのメートル(軸) > self.軸に沿った長さのメートル(最長) {
                軸
            } else {
                最長
            }
        })
    }

    pub(super) fn 軸の順に並べた両端を読む(&self) -> ([f64; 3], [f64; 3]) {
        (self.最小の端, self.最大の端)
    }

    pub(super) fn 軸の順に並べた両端から組む(最小の端: [f64; 3], 最大の端: [f64; 3]) -> Self {
        Self { 最小の端, 最大の端 }
    }
}

// 位置の3成分を軸の順に並べる。軸ごとに同じ式を当てる操作がこれを通して読む。
fn 成分を軸の順に並べる(位置: 形の局所座標の位置) -> [f64; 3] {
    [位置.xのメートル(), 位置.yのメートル(), 位置.zのメートル()]
}
