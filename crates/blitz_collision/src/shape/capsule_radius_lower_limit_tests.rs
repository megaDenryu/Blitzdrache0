//! 半径の下限の反証。指摘された反例の半径が生成の段階で拒まれること、下限ちょうどが受け付けられること、
//! 掃引の変位を添えた生成も同じ下限で拒むことを見る。
//!
//! 指摘された反例は、半径が10のマイナス200乗メートルの2つの球を3かける10のマイナス200乗メートル離した対で
//! ある。触れていないのに隔たりの二乗も半径の和の二乗も0へ落ちるため、下限を課す前は掃引の始まりから
//! 触れているものとして扱われていた。下限を課した後は形を作る手前で拒まれるため、この反証は掃引の答えでなく
//! 生成の破れとして書く。

use super::capsule::カプセル;
use super::capsule_error::カプセルの生成エラー;
use super::capsule_radius_lower_limit::カプセルの半径の下限メートル;
use super::local_displacement::形の局所座標の変位;
use super::local_position::形の局所座標の位置;
use super::sweep_capsule::形を掃引するカプセル;

fn 原点() -> 形の局所座標の位置 {
    match 形の局所座標の位置::生成する(0.0, 0.0, 0.0) {
        Ok(位置) => 位置,
        Err(誤り) => panic!("試験用の原点を作れなかった: {誤り}"),
    }
}

fn 動かない変位() -> 形の局所座標の変位 {
    match 形の局所座標の変位::生成する(0.0, 0.0, 0.0) {
        Ok(変位) => 変位,
        Err(誤り) => panic!("試験用の動かない変位を作れなかった: {誤り}"),
    }
}

#[test]
fn 下限を下回る半径のカプセルは型付きエラーで拒む() {
    assert_eq!(
        カプセル::生成する(原点(), 原点(), 1.0e-200),
        Err(カプセルの生成エラー::カプセルの半径が下限を下回っている)
    );
}

#[test]
fn 下限ちょうどの半径のカプセルは受け付ける() {
    assert!(カプセル::生成する(原点(), 原点(), f64::from(カプセルの半径の下限メートル)).is_ok());
}

#[test]
fn 掃引の変位を添えた生成も下限を下回る半径を拒む() {
    assert_eq!(
        形を掃引するカプセル::生成する(原点(), 原点(), 1.0e-200, 動かない変位()),
        Err(カプセルの生成エラー::カプセルの半径が下限を下回っている)
    );
}
