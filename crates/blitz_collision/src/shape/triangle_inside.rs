//! 三角形の平面の上の点が、三角形の内側(辺の上と頂点を含む)にあるかの判定と、その点がどの特徴に載っているかの
//! 読み取り。受け取るのは平面の上の点、返すのは3辺それぞれについての符号である。
//!
//! 型の代数と別のファイルへ置くのは、これが1つの独立した工程だからである。3辺それぞれについて、辺の変位と
//! 辺の始点から点への変位の外積を取り、面に垂直な変位との内積の符号を見る。3つとも負でなければ内側であり、
//! 零になった辺はその辺の直線の上に点が載っていることを意味する。
//!
//! 判定の基準に面の単位法線でなく面に垂直な変位を使うのは、1に正す割り算を通さないためである。割り算は符号を
//! 変えないが、通さなければ零がそのまま零で残る。零の並びから当たった特徴(面・辺・頂点)が決まるため、
//! この等号は丸めた値どうしの厳密な比較で見る。近い値を同じとみなす幅を置くと、幅の中の位置で答えが面と辺の
//! 間を揺れるからである。
//!
//! 面の向きを備えた三角形の側へ置くのは、面に垂直な変位を点1つごとに外積で求め直さないためである。三角形網の
//! 問い合わせは候補1枚につきこの判定を何度も通るため、求め直すと外積が候補の数だけ増える。

use super::local_position::形の局所座標の位置;
use super::triangle_vertex_number::三角形の頂点の番号;
use super::triangle_with_orientation::面の向きを備えた三角形;

impl 面の向きを備えた三角形 {
    /// 面の上の点が三角形の内側(辺の上と頂点を含む)にあるか。
    pub fn 面の上の点が内側にあるか(&self, 点: 形の局所座標の位置) -> bool {
        self.辺ごとの符号を求める(点).into_iter().all(|符号| 符号 >= 0.0)
    }

    /// 辺ごとの符号を、頂点の番号の並びで返す。負の値は点がその辺の外側に在ること、零はその辺の直線の上に
    /// 載っていること、正は内側に在ることを表す。
    pub fn 辺ごとの符号を求める(&self, 点: 形の局所座標の位置) -> [f64; 3] {
        let 垂直な変位 = self.面に垂直な変位();
        三角形の頂点の番号::並べる().map(|番号| {
            let 始点 = self.頂点の位置(番号);
            let 辺 = self.辺の変位を求める(番号);
            辺.外積(始点.終点までの変位を求める(点)).内積(垂直な変位)
        })
    }
}
