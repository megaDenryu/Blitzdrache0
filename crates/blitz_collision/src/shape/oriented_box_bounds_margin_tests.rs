//! 合成の精度と余白の基準の反証。細長い直方体を回した姿勢では、真の広がりが軸の長さよりはるかに小さくなる一方、
//! 丸めの絶対誤差は軸の長さに比例したまま残る。この差が箱を実体より小さくしないことを見る。
//!
//! 3つを見る。長い半軸がほぼ直交へ回った箱で単精度の角が入ること、単精度で合成すると真の広がりに届かない姿勢で
//! 倍精度の角が入ること、そして影の側の幅が締まったままであることである。2つ目が本体であり、その姿勢は
//! 20万通りの無作為な四元数と半分の長さの組から、単精度の合成と余白では真の広がりを1パーセント下回るものを
//! 探して選んだ。
//!
//! 3つ目を置くのは、包むだけなら半分の長さの総和をそのまま余白にすれば足りるためである。それでは箱が実体の
//! 何万倍にも広がり、粗い選別が候補を絞る道具でなくなる。

use blitz_math::{クォータニオン, ローカル};

use super::oriented_box::任意姿勢の直方体;
use super::oriented_box_bounds_fixture::{
    倍精度で評価した8つの角を並べる, 単精度で評価した8つの角を並べる, 天頂まわりの4分の1回転, 直方体を作る, 箱の2つの端を並べる,
};

// 長い軸の半分の長さ。単精度の刻みを掛けた誤差が短い軸の長さを大きく上回るように選ぶ。
const 長い軸の半分の長さメートル: f32 = 100_000.0;
const 短い軸の半分の長さメートル: f32 = 0.001;

fn 天頂まわりに4分の1だけ回した細長い箱() -> 任意姿勢の直方体 {
    直方体を作る(
        [0.0, 0.0, 0.0],
        天頂まわりの4分の1回転(),
        [長い軸の半分の長さメートル, 短い軸の半分の長さメートル, 短い軸の半分の長さメートル],
    )
}

#[test]
fn 長い半軸がほぼ直交へ回った箱でも単精度の角が入る() {
    let 直方体 = 天頂まわりに4分の1だけ回した細長い箱();
    let (最小, 最大) = 箱の2つの端を並べる(&直方体);
    for (番号, 角) in 単精度で評価した8つの角を並べる(&直方体).into_iter().enumerate() {
        for 軸 in 0usize..3 {
            assert!(最小[軸] <= 角[軸] && 角[軸] <= 最大[軸], "角{番号}の軸{軸}が箱の外にある");
        }
    }
}

#[test]
fn 単精度で合成すると真の広がりに届かない姿勢でも倍精度の角が入る() {
    let 回転 = match クォータニオン::<ローカル, ローカル>::生成する(0.772_855_5, 0.880_855_56, -0.295_562_27, -0.259_322_17) {
        Ok(回転) => 回転,
        Err(誤り) => panic!("試験用の回転を作れなかった: {誤り}"),
    };
    let 直方体 = 直方体を作る([0.0, 0.0, 0.0], 回転, [107.463_03, 3.861_696_6e-7, 3.861_696_6e-7]);
    let (最小, 最大) = 箱の2つの端を並べる(&直方体);
    for (番号, 角) in 倍精度で評価した8つの角を並べる(&直方体).into_iter().enumerate() {
        for 軸 in 0usize..3 {
            assert!(
                f64::from(最小[軸]) <= 角[軸] && 角[軸] <= f64::from(最大[軸]),
                "角{番号}の軸{軸}が箱の外にある"
            );
        }
    }
}

#[test]
fn 長い半軸が直交へ回っても影の側の幅は締まったままになる() {
    let 直方体 = 天頂まわりに4分の1だけ回した細長い箱();
    let (最小, 最大) = 箱の2つの端を並べる(&直方体);
    let 東西の幅 = 最大[0] - 最小[0];
    assert!(
        東西の幅 <= 長い軸の半分の長さメートル / 10_000.0,
        "影の側の幅{東西の幅}メートルが長い軸の1万分の1を越えている"
    );
}
