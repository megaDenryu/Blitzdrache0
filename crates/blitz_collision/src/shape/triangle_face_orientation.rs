//! 三角形の面の向き: 頂点の並びから外積で組んだ面に垂直な変位と、それを長さ1に正した単位法線の変位を1つに
//! まとめたものである。受け取るのは三角形、返すのはこの2つの変位である。
//!
//! 2つを1つの型が持つのは、どちらも同じ1回の外積から導かれ、片方だけを別の三角形から取ると答えが食い違うため
//! である。正していない変位が要るのは内外の判定であり、1に正す割り算を通さなければ零がそのまま零で残って
//! 当たった特徴を厳密な比較で決められる。長さ1の変位が要るのは掃引の面の方程式と接触の単位法線を組む地点である。
//!
//! 三角形そのものを含めずにこの2つだけを持つ型にするのは、三角形網が三角形1枚ごとにこれを保持し、頂点は頂点の
//! 列から番号で引くためである。頂点まで含めて持つと、頂点の列を1つ持ったうえで三角形1枚につき3つの頂点を
//! 二重に持つことになる。
//! 参照: `crates/blitz_collision/src/triangle_mesh/mesh.rs`

use super::local_displacement::形の局所座標の変位;
use super::triangle::局所座標の三角形;

/// 三角形の面の向き。面に垂直な変位と、それを長さ1に正した単位法線の変位を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 三角形の面の向き {
    面に垂直な変位: 形の局所座標の変位,
    単位法線の変位: 形の局所座標の変位,
}

impl 三角形の面の向き {
    /// 三角形から求める。面積が零で向きが定まらない三角形では値なしを返す。外積と平方根はここで通る。
    pub fn 三角形から求める(三角形: &局所座標の三角形) -> Option<Self> {
        Some(Self {
            面に垂直な変位: 三角形.面に垂直な変位を求める(),
            単位法線の変位: 三角形.面の単位法線の変位を求める()?,
        })
    }

    /// 長さを1に正していない、面に垂直な変位。長さは三角形の面積の2倍である。
    pub fn 面に垂直な変位(&self) -> 形の局所座標の変位 {
        self.面に垂直な変位
    }

    /// 面に垂直な変位を長さ1に正したもの。
    pub fn 単位法線の変位(&self) -> 形の局所座標の変位 {
        self.単位法線の変位
    }
}
