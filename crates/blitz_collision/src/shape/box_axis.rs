//! 直方体自身の座標軸: 回転を掛ける前の直方体が持つ3本の軸のどれかである。
//!
//! 添字の数で指さないのは、面・辺・頂点を指す答えがこの軸を持って返るためであり、裸の数では0が何の軸かを
//! 呼び出し側が別の決まりで覚えることになるからである。並びは軸ごとの半分の長さのx・y・zと同じである。
//!
//! 次の軸は巡回で決める。辺は1本の軸に沿って伸び、残る2本の軸のそれぞれについて正負どちらの側に在るかで
//! 場所が決まるため、「残る2本」を並びの順で言うための決まりが要る。

/// 回転を掛ける前の直方体が持つ3本の軸のどれか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 直方体自身の座標軸 {
    /// 軸ごとの半分の長さのx成分に対応する軸。
    X軸,
    /// 軸ごとの半分の長さのy成分に対応する軸。
    Y軸,
    /// 軸ごとの半分の長さのz成分に対応する軸。
    Z軸,
}

impl 直方体自身の座標軸 {
    /// 3本の軸を、求解が候補を数える順に並べる。
    pub fn 並べる() -> [Self; 3] {
        [Self::X軸, Self::Y軸, Self::Z軸]
    }

    /// 巡回の順で次に来る軸。x軸の次はy軸、y軸の次はz軸、z軸の次はx軸である。
    pub fn 次の軸(self) -> Self {
        match self {
            Self::X軸 => Self::Y軸,
            Self::Y軸 => Self::Z軸,
            Self::Z軸 => Self::X軸,
        }
    }

    /// 軸ごとに3つ並べた組の中でこの軸が占める位置。
    pub fn 並びの位置(self) -> usize {
        match self {
            Self::X軸 => 0,
            Self::Y軸 => 1,
            Self::Z軸 => 2,
        }
    }
}
