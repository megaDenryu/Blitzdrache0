//! 直方体の軸ごとの半分の長さ: 直方体の中心から面までの、その直方体自身の3軸に沿った長さ。
//!
//! 位置でも変位でもなく長さの組で持つのは、この量が座標系の原点に依らず、回転を掛けても変わらないためである。
//! 負の値は面の裏返しであり、重なりの判定を無意味にするため生成が拒む。
//! 上限を課すのは、外接する軸平行の直方体の合成が単精度の範囲を出ないことを保証するためである。
//! 上限とその算術は `crates/blitz_collision/src/shape/coordinate_limit.rs` にある。
//!
//! 0の扱いは軸の数で分かれる。0が高々1軸なら受け入れる。厚みの無い板として据えた部品がありうるためである。
//! 2軸以上が0の組は線分か点へ退化しており、生成が型付きエラーで拒む。
//! 退化した形は面を持たないため、参照面と入射面の切り抜きが同じ位置の接触点を重ねて作る。
//! 中心が同じ点どうし(3軸が0)では1点の接触が4件になり、同じ向きの線分どうし(2軸が0)では2つの位置へ重複する。
//! 同じ穴は接触点集合に限らず、面と辺と頂点を数え上げる詳細判定と掃引の全経路へ同型で入る。
//! 経路ごとに退化を場合分けすると数え上げの決まりが経路の数だけ増えるため、形の入口1箇所で閉じる。

use blitz_math::メートル;

use super::coordinate_limit::形状の座標の絶対値の上限メートル;
use super::error::{直方体の生成エラー, 軸名一覧};

// 長さが0であってよい軸の数の上限。1軸だけの0は厚みの無い板であり、2軸以上の0は線分か点への退化である。
const 長さが零であってよい軸の数の上限: usize = 1;

/// 直方体の中心から面までの、その直方体自身の3軸に沿った長さ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 直方体の軸ごとの半分の長さ {
    成分: [メートル; 3],
}

impl 直方体の軸ごとの半分の長さ {
    /// 負の長さ・有限でない長さ・上限を越えた長さ・2軸以上が0の退化した組を型付きエラーで拒む。
    pub fn 生成する(成分: [メートル; 3]) -> Result<Self, 直方体の生成エラー> {
        for (軸, 値) in 軸名一覧.into_iter().zip(成分) {
            if !値.値().is_finite() || 値.値() < 0.0 {
                return Err(直方体の生成エラー::半分の長さが負か非有限 { 軸 });
            }
            if 値.値() > 形状の座標の絶対値の上限メートル {
                return Err(直方体の生成エラー::半分の長さが上限を越えている { 軸 });
            }
        }
        if 成分.into_iter().filter(|値| 値.値() == 0.0).count() > 長さが零であってよい軸の数の上限 {
            return Err(直方体の生成エラー::半分の長さが2軸以上で零);
        }
        Ok(Self { 成分 })
    }

    /// 直方体自身の東西の軸に沿った半分の長さ。
    pub fn x(&self) -> メートル {
        self.成分[0]
    }

    /// 直方体自身の天頂の軸に沿った半分の長さ。
    pub fn y(&self) -> メートル {
        self.成分[1]
    }

    /// 直方体自身の南北の軸に沿った半分の長さ。
    pub fn z(&self) -> メートル {
        self.成分[2]
    }
}
