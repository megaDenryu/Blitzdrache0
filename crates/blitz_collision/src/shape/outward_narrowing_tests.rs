//! 外向きに丸めて狭める境界の反証。
//!
//! 見るのは4つである。単精度で表せる値がそのまま返ること、表せない値が正しい側へ1刻みだけ出ること、符号が負でも
//! 向きが入れ替わらないこと、そして単精度の正規化数の下限を下回る値でも向きが守られることである。3つ目を別に
//! 見るのは、零へ向けた丸めが負の値では大きい側への丸めになり、1刻み動かす向きが正の値と逆になるためである。

use super::outward_narrowing::{
    倍精度の値を大きい側へ丸めて単精度へ狭める, 倍精度の値を小さい側へ丸めて単精度へ狭める
};

// 単精度で表せない値。1に単精度の刻みの半分を足したものであり、1と1の次の単精度の値のちょうど中間にある。
fn 単精度の刻みの半分だけ1を越えた値() -> f64 {
    1.0 + f64::from(f32::EPSILON) / 2.0
}

#[test]
fn 単精度で表せる値はどちらの向きでも動かない() {
    for 値 in [0.0_f32, 1.0, -1.0, 0.5, -1024.25, f32::MIN_POSITIVE] {
        assert_eq!(倍精度の値を大きい側へ丸めて単精度へ狭める(f64::from(値)), 値);
        assert_eq!(倍精度の値を小さい側へ丸めて単精度へ狭める(f64::from(値)), 値);
    }
}

#[test]
fn 表せない値は挟む2つの単精度へ分かれる() {
    let 値 = 単精度の刻みの半分だけ1を越えた値();
    assert_eq!(倍精度の値を小さい側へ丸めて単精度へ狭める(値), 1.0_f32);
    assert_eq!(倍精度の値を大きい側へ丸めて単精度へ狭める(値), 1.0_f32.next_up());
    assert_eq!(倍精度の値を大きい側へ丸めて単精度へ狭める(-値), -1.0_f32);
    assert_eq!(倍精度の値を小さい側へ丸めて単精度へ狭める(-値), (-1.0_f32).next_down());
}

#[test]
fn 狭めた値は必ず元の値を挟む() {
    let 調べる値 = [
        1.0e-30_f64,
        -1.0e-30,
        1.0e30,
        -1.0e30,
        std::f64::consts::PI,
        -std::f64::consts::PI,
        1.0 / 3.0,
        -1.0 / 3.0,
        単精度の刻みの半分だけ1を越えた値(),
        f64::from(f32::MIN_POSITIVE) / 2.0,
        -f64::from(f32::MIN_POSITIVE) / 2.0,
    ];
    for 値 in 調べる値 {
        let 下 = 倍精度の値を小さい側へ丸めて単精度へ狭める(値);
        let 上 = 倍精度の値を大きい側へ丸めて単精度へ狭める(値);
        assert!(f64::from(下) <= 値, "{値}の小さい側が元の値を越えている");
        assert!(f64::from(上) >= 値, "{値}の大きい側が元の値に届いていない");
    }
}
