//! 大域の値と、軸の順に並んだ3成分の間の換算。受け取るのは位置と変位、返すのは軸の順に並べた3成分であり、
//! 逆向きに3成分から大域の位置を組む口も持つ。
//!
//! 箱の端の計算は3軸に同じ式を当てるため配列で書くのが素直だが、配列は成分の意味を型で持たない。換算をここへ
//! 集めるのは、軸の並び(東・天頂・南)を添字へ写す綴りの持ち主を1つに決めるためである。並びを変えるときに直す
//! ところがこのファイルだけになり、箱の側は添字がどの軸を指すかを知らないままでいられる。
//!
//! 注意: 換算は`shape`の配下から見える形で公開する。Rustが兄弟のモジュール1つだけへ見せる書き方を持たないため
//! であり、使ってよいのは箱の端の計算だけである。
//! 参照: `crates/blitz_collision/src/shape/global_axis_aligned_box.rs`

use blitz_math::{メートル, ローカル, ワールド, 位置, 変位, 大域メートル, 大域ワールド位置};

// 大域の位置の3成分を軸の順に並べる。
pub(super) fn 大域の位置の成分を軸の順に並べる(位置: 大域ワールド位置) -> [f64; 3] {
    [位置.x().値(), 位置.y().値(), 位置.z().値()]
}

// 変位のうち先頭の比のぶんだけの移動を、軸の順に並べる。単精度から倍精度への変換は丸めを1つも通さない。
pub(super) fn 変位の先頭の比のぶんだけの移動を軸の順に並べる(変位: 変位<ワールド>, 比: f64) -> [f64; 3] {
    [変位.x(), 変位.y(), 変位.z()].map(|成分| f64::from(成分.値()) * 比)
}

// 局所の位置の3成分を軸の順に並べる。単精度のまま返し、倍精度への変換は箱の側が行う。
pub(super) fn 局所の位置の成分を軸の順に並べる(端: 位置<ローカル>) -> [メートル; 3] {
    [端.x(), 端.y(), 端.z()]
}

// 軸の順に並んだ3成分を大域の位置へ戻す。
pub(super) fn 軸の順の3成分から大域の位置を組む(成分: [f64; 3]) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(成分[0]),
        大域メートル::生成する(成分[1]),
        大域メートル::生成する(成分[2]),
    )
}
