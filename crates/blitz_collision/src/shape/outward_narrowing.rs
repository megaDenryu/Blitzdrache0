//! 倍精度で組み立てた値を、単精度へ外向きに丸めて狭める境界。受け取るのは倍精度の値、返すのは単精度である。
//!
//! 丸めの向きを最近接でなく外向きに固定するのは、狭める丸めで箱の端が内側へ動くと、直方体の面のちょうど上を通る
//! 問い合わせを粗い選別が落とすためである。落とす側の誤りは詳細判定で取り返せないのに対し、広く取る側の誤りは
//! 詳細判定が候補を1件余計に捨てるだけである。
//!
//! 手順は2段である。まず絶対値が入力を越えない単精度の値を作り、次に向きが足りなければ隣の単精度へ1つ動かす。
//! 前段は指数と仮数を組み直して仮数を切り捨てるだけであるから、得た値は入力を挟む2つの単精度のうち零に近い側で
//! あり、隣へ1つ動かせば必ず反対側の外へ出る。標準ライブラリが倍精度から単精度への型付き変換を持たず、数値の
//! `as`キャストが規約で禁じられているため、この組み直しを自分で書く。
//!
//! 単精度の正規化数の下限(2の126乗分の1)を下回る入力は前段で零へ落とし、外向きの側はその下限そのものを返す。
//! 非正規化数の刻みまで詰める代わりに、外側へ最大で2の126乗分の1メートルだけ広く取る。この幅は形状の座標が
//! 意味を持つ範囲に存在しない。
//!
//! 前提: 入力は有限であり、絶対値が単精度の最大値に収まる。越えた入力に対しても外向きの側は無限大を返して内側へ
//! 縮まないが、そこまで大きい値は形状の座標の上限が入口で拒む。

const 単精度の符号のビット: u32 = 0x8000_0000;
const 倍精度の指数のマスク: u64 = 0x7ff;
const 倍精度の仮数のマスク: u64 = 0x000f_ffff_ffff_ffff;
const 倍精度の仮数のビット数: u32 = 52;
const 単精度の仮数のビット数: u32 = 23;
const 仮数のビット数の差: u32 = 29;
const 倍精度の指数のずらし: i32 = 1023;
const 指数のずらしの差: u64 = 896; // 倍精度のずらし1023から単精度のずらし127を引いた値
const 単精度の最小の正規化数の2進指数: i32 = -126;
const 単精度の最大の2進指数: i32 = 127;

/// 入力以上で最も入力に近い単精度の値。箱の最大の端がこれを通る。
pub(super) fn 倍精度の値を大きい側へ丸めて単精度へ狭める(値: f64) -> f32 {
    let 零へ寄せた値 = 倍精度の値を零へ向けて丸めて単精度へ狭める(値);
    if f64::from(零へ寄せた値) >= 値 {
        return 零へ寄せた値;
    }
    if 零へ寄せた値 == 0.0 {
        return f32::MIN_POSITIVE;
    }
    零へ寄せた値.next_up()
}

/// 入力以下で最も入力に近い単精度の値。箱の最小の端がこれを通る。
pub(super) fn 倍精度の値を小さい側へ丸めて単精度へ狭める(値: f64) -> f32 {
    let 零へ寄せた値 = 倍精度の値を零へ向けて丸めて単精度へ狭める(値);
    if f64::from(零へ寄せた値) <= 値 {
        return 零へ寄せた値;
    }
    if 零へ寄せた値 == 0.0 {
        return -f32::MIN_POSITIVE;
    }
    零へ寄せた値.next_down()
}

// 絶対値が入力を越えない単精度の値。単精度の正規化数の下限を下回る入力は符号を保った零へ落とす。
fn 倍精度の値を零へ向けて丸めて単精度へ狭める(値: f64) -> f32 {
    let ビット = 値.to_bits();
    let 符号 = if 値.is_sign_negative() { 単精度の符号のビット } else { 0 };
    let 生の指数 = ビット列の下位16ビットを取り出す((ビット >> 倍精度の仮数のビット数) & 倍精度の指数のマスク);
    let 指数 = i32::from(生の指数) - 倍精度の指数のずらし;
    if 生の指数 == 0 || 指数 < 単精度の最小の正規化数の2進指数 {
        return f32::from_bits(符号);
    }
    if 指数 > 単精度の最大の2進指数 {
        return f32::from_bits(符号 | f32::MAX.to_bits());
    }
    let 単精度の指数部 = u64::from(生の指数) - 指数のずらしの差;
    let 単精度の仮数 = (ビット & 倍精度の仮数のマスク) >> 仮数のビット数の差;
    f32::from_bits(符号 | ビット列の下位32ビットを取り出す((単精度の指数部 << 単精度の仮数のビット数) | 単精度の仮数))
}

// 桁の切り出しをバイト列の分解で書くのは、数値の`as`キャストが規約で禁じられており、`try_from`で失敗しえない
// 変換に失敗の枝を作らないためである。
fn ビット列の下位16ビットを取り出す(値: u64) -> u16 {
    let [_, _, _, _, _, _, 上位, 下位] = 値.to_be_bytes();
    u16::from_be_bytes([上位, 下位])
}

fn ビット列の下位32ビットを取り出す(値: u64) -> u32 {
    let [_, _, _, _, 第1, 第2, 第3, 第4] = 値.to_be_bytes();
    u32::from_be_bytes([第1, 第2, 第3, 第4])
}
