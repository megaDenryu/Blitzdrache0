//! 三角形の頂点の番号: 1つの三角形が持つ3つの頂点のうちどれかを指す。
//!
//! 裸の添字で指さないのは、当たった特徴がこの番号を持って返るためであり、数の0が何番目の頂点かを
//! 呼び出し側が別の決まりで覚えることになるからである。3つ以外の値を作れないことも型が担う。
//!
//! 辺もこの番号1つで指す。番号の頂点から次の番号の頂点へ張ったものがその辺であり、3つの番号で3辺が尽きる。

/// 1つの三角形が持つ3つの頂点のうちどれか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 三角形の頂点の番号 {
    /// 三角形を生成したときに並べた3つの頂点のうち先頭のもの。
    第1の頂点,
    /// 三角形を生成したときに並べた3つの頂点のうち2番目のもの。
    第2の頂点,
    /// 三角形を生成したときに並べた3つの頂点のうち3番目のもの。
    第3の頂点,
}

impl 三角形の頂点の番号 {
    /// 3つの頂点を、求解が候補を数える順に並べる。
    pub fn 並べる() -> [Self; 3] {
        [Self::第1の頂点, Self::第2の頂点, Self::第3の頂点]
    }

    /// 巡回の順で次に来る頂点。第1の次は第2、第2の次は第3、第3の次は第1である。
    pub fn 次の頂点(self) -> Self {
        match self {
            Self::第1の頂点 => Self::第2の頂点,
            Self::第2の頂点 => Self::第3の頂点,
            Self::第3の頂点 => Self::第1の頂点,
        }
    }

    /// 3つ並べた組の中でこの頂点が占める位置。
    pub fn 並びの位置(self) -> usize {
        match self {
            Self::第1の頂点 => 0,
            Self::第2の頂点 => 1,
            Self::第3の頂点 => 2,
        }
    }
}
