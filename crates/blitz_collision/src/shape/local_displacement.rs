//! 形の局所座標の変位: 形が共有する局所座標系での、2つの位置の差である。成分の並びはx・y・zであり、
//! 単位はメートル、精度は倍精度である。
//!
//! 位置と別の型にするのは、位置どうしの加算に意味が無く、位置から位置を引いた量だけが向きと長さを持つためである。
//! 内積・外積・長さの二乗をこの型が持つのは、線分の交差と掃引の接触の求解がこの3つと定数倍だけで書けるからであり、
//! 3つの成分を裸で持ち回すとxとzを取り違えても型が通るためである。
//!
//! 演算の結果は有限性を検査し直さない。生成の検査が成分の絶対値を上限に収めており、その上限から
//! 内積・外積・実数倍を重ねた掃引の係数と判別式が倍精度の範囲を出ないことを算術で示せるためである。
//! 上限とその算術は `crates/blitz_collision/src/oriented_box.rs` にある。

use super::coordinate_limit::形状の座標の絶対値の上限メートル;
use super::local_axis::形の局所座標の軸;
use super::local_error::形の局所座標の生成エラー;

/// 形が共有する局所座標系での、2つの位置の差。成分の並びはx・y・zであり、単位はメートルである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 形の局所座標の変位 {
    xのメートル: f64,
    yのメートル: f64,
    zのメートル: f64,
}

impl 形の局所座標の変位 {
    /// 成分が有限でありその絶対値が上限に収まることを確かめて作る。
    pub fn 生成する(xのメートル: f64, yのメートル: f64, zのメートル: f64) -> Result<Self, 形の局所座標の生成エラー> {
        if [xのメートル, yのメートル, zのメートル].into_iter().any(|値| !値.is_finite()) {
            return Err(形の局所座標の生成エラー::変位の成分が有限でない);
        }
        if [xのメートル, yのメートル, zのメートル]
            .into_iter()
            .any(|値| 値.abs() > f64::from(形状の座標の絶対値の上限メートル))
        {
            return Err(形の局所座標の生成エラー::変位の成分の絶対値が上限を越えている);
        }
        Ok(Self::演算の結果から組む(xのメートル, yのメートル, zのメートル))
    }

    // どこへも進まない変位。軸ごとの寄与を畳んで組み立てる操作の始まりに使う。
    pub(crate) fn 零() -> Self {
        Self::演算の結果から組む(0.0, 0.0, 0.0)
    }

    pub(crate) fn 演算の結果から組む(xのメートル: f64, yのメートル: f64, zのメートル: f64) -> Self {
        Self {
            xのメートル,
            yのメートル,
            zのメートル,
        }
    }

    /// 局所座標系のx軸に沿って測ったメートル。
    pub fn xのメートル(&self) -> f64 {
        self.xのメートル
    }

    /// 局所座標系のy軸に沿って測ったメートル。
    pub fn yのメートル(&self) -> f64 {
        self.yのメートル
    }

    /// 局所座標系のz軸に沿って測ったメートル。
    pub fn zのメートル(&self) -> f64 {
        self.zのメートル
    }

    // 軸に沿って測ったメートル。軸を値で受ける読み口があると、軸を選んでから成分を読む工程が成分の綴りを持たずに済む。
    pub(crate) fn 軸に沿ったメートル(self, 軸: 形の局所座標の軸) -> f64 {
        match 軸 {
            形の局所座標の軸::X軸 => self.xのメートル,
            形の局所座標の軸::Y軸 => self.yのメートル,
            形の局所座標の軸::Z軸 => self.zのメートル,
        }
    }

    // 成分の絶対値が最も大きい軸。並んだときは並びの先の軸を選ぶ。3つとも零で軸が定まらないなら値なしを返す。
    pub(crate) fn 絶対値が最も大きい軸を求める(self) -> Option<形の局所座標の軸> {
        let mut 最も大きい軸 = 形の局所座標の軸::X軸;
        for 軸 in [形の局所座標の軸::Y軸, 形の局所座標の軸::Z軸] {
            if self.軸に沿ったメートル(軸).abs() > self.軸に沿ったメートル(最も大きい軸).abs() {
                最も大きい軸 = 軸;
            }
        }
        (self.軸に沿ったメートル(最も大きい軸) != 0.0).then_some(最も大きい軸)
    }

    pub(crate) fn 加える(self, 相手: Self) -> Self {
        Self::演算の結果から組む(
            self.xのメートル + 相手.xのメートル,
            self.yのメートル + 相手.yのメートル,
            self.zのメートル + 相手.zのメートル,
        )
    }

    pub(crate) fn 引く(self, 相手: Self) -> Self {
        Self::演算の結果から組む(
            self.xのメートル - 相手.xのメートル,
            self.yのメートル - 相手.yのメートル,
            self.zのメートル - 相手.zのメートル,
        )
    }

    pub(crate) fn 実数倍する(self, 倍率: f64) -> Self {
        Self::演算の結果から組む(self.xのメートル * 倍率, self.yのメートル * 倍率, self.zのメートル * 倍率)
    }

    pub(crate) fn 内積(self, 相手: Self) -> f64 {
        self.xのメートル * 相手.xのメートル + self.yのメートル * 相手.yのメートル + self.zのメートル * 相手.zのメートル
    }

    pub(crate) fn 外積(self, 相手: Self) -> Self {
        Self::演算の結果から組む(
            self.yのメートル * 相手.zのメートル - self.zのメートル * 相手.yのメートル,
            self.zのメートル * 相手.xのメートル - self.xのメートル * 相手.zのメートル,
            self.xのメートル * 相手.yのメートル - self.yのメートル * 相手.xのメートル,
        )
    }

    pub(crate) fn 長さの二乗(self) -> f64 {
        self.内積(self)
    }
}
