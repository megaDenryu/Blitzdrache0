//! 形の局所座標の位置: 複数の形が共有する1つの局所座標系での位置である。成分の並びはx・y・zであり、
//! 単位はメートル、精度は倍精度である。
//!
//! `blitz_math`の`位置`と別の型にするのは、あちらが単精度であるためである。形そのものは単精度で持つが、
//! 問い合わせは大域の倍精度の位置から来る。形の側の精度へ先に狭めると、原点から遠い場所で問い合わせの点が
//! 単精度の刻みぶん動き、その動きが当たり判定の答えになる。狭めるのは答えを外へ返す境界だけにする。
//!
//! 成分の絶対値の上限は問い合わせの入力へ課す。入力が上限に収まっていれば、掃引の2次方程式の係数と判別式が
//! 桁あふれしないことを算術で示せるためである(`crates/blitz_collision/src/oriented_box.rs`)。
//! 入力から導いた点は上限の外へ出うるため、有限性だけを見る別の入口を通す。

use super::coordinate_limit::形状の座標の絶対値の上限メートル;
use super::local_displacement::形の局所座標の変位;
use super::local_error::形の局所座標の生成エラー;

/// 複数の形が共有する1つの局所座標系での位置。成分の並びはx・y・zであり、単位はメートルである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 形の局所座標の位置 {
    xのメートル: f64,
    yのメートル: f64,
    zのメートル: f64,
}

impl 形の局所座標の位置 {
    /// 問い合わせの入力としての位置を作る。成分が有限でありその絶対値が上限に収まることを確かめる。
    pub fn 生成する(xのメートル: f64, yのメートル: f64, zのメートル: f64) -> Result<Self, 形の局所座標の生成エラー> {
        let 位置 = Self::演算の結果から組む(xのメートル, yのメートル, zのメートル)?;
        if [xのメートル, yのメートル, zのメートル]
            .into_iter()
            .any(|値| 値.abs() > f64::from(形状の座標の絶対値の上限メートル))
        {
            return Err(形の局所座標の生成エラー::位置の成分の絶対値が上限を越えている);
        }
        Ok(位置)
    }

    // 求解の途中で導いた点。上限は入力へ課すものであり、導いた点は上限の外へ出うるため有限性だけを確かめる。
    pub(crate) fn 演算の結果から組む(
        xのメートル: f64,
        yのメートル: f64,
        zのメートル: f64,
    ) -> Result<Self, 形の局所座標の生成エラー> {
        if [xのメートル, yのメートル, zのメートル].into_iter().any(|値| !値.is_finite()) {
            return Err(形の局所座標の生成エラー::位置の成分が有限でない);
        }
        Ok(Self {
            xのメートル,
            yのメートル,
            zのメートル,
        })
    }

    // 呼び出し側の算術が有限性を済ませている場合の入口。直方体の中心は単精度の有限値から広げた値であり、
    // 倍精度で有限であることが単精度の検査から導ける。
    pub(crate) fn 検査済みの成分から組む(xのメートル: f64, yのメートル: f64, zのメートル: f64) -> Self {
        Self {
            xのメートル,
            yのメートル,
            zのメートル,
        }
    }

    /// 局所座標系のx軸に沿って測ったメートル。
    pub fn xのメートル(&self) -> f64 {
        self.xのメートル
    }

    /// 局所座標系のy軸に沿って測ったメートル。
    pub fn yのメートル(&self) -> f64 {
        self.yのメートル
    }

    /// 局所座標系のz軸に沿って測ったメートル。
    pub fn zのメートル(&self) -> f64 {
        self.zのメートル
    }

    /// この位置から終点へ向かう変位。
    pub fn 終点までの変位を求める(&self, 終点: Self) -> 形の局所座標の変位 {
        形の局所座標の変位::演算の結果から組む(
            終点.xのメートル - self.xのメートル,
            終点.yのメートル - self.yのメートル,
            終点.zのメートル - self.zのメートル,
        )
    }

    /// 変位だけ進んだ位置。成分が有限でなくなる入力を型付きエラーで拒む。求解が導く点であるため、
    /// 成分の絶対値の上限は課さない。
    pub fn 変位だけ進んだ位置を求める(&self, 変位: 形の局所座標の変位) -> Result<Self, 形の局所座標の生成エラー> {
        Self::演算の結果から組む(
            self.xのメートル + 変位.xのメートル(),
            self.yのメートル + 変位.yのメートル(),
            self.zのメートル + 変位.zのメートル(),
        )
    }
}
