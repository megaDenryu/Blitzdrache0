//! 大域の軸平行の直方体: 世界の原点を基準にした倍精度の、座標軸に平行な直方体である。
//!
//! 単精度の`軸平行の直方体`と別の型にするのは、世界の広がりが単精度の刻みで表せる範囲を越えるためである。
//! 問い合わせの覆いはプレイヤーの居る場所の大域の座標で来るため、その比較を単精度で行うと、原点から遠い場所で
//! 箱の端が実際の形の何倍もの幅で動く。
//!
//! 群のローカル空間の箱を、その群の大域原点を足してこの型へ広げる向きで比較を揃える。逆向き(覆いを単精度へ狭める)
//! にしないのは、狭める側に丸めが入り、覆いが実体より小さく出た場合に候補を落とすためである。単精度から倍精度へ
//! 広げる変換は丸めを1つも通さないため、広げる向きなら覆いも形も動かない。

use blitz_math::{メートル, ローカル, ワールド, 位置, 変位, 大域メートル, 大域ワールド位置};

use super::axis_aligned_box::軸平行の直方体;
use super::truncation_rounding_margin::{
    掃引の切り詰めが受ける丸めを包む幅を求める, 線分の切り詰めが受ける丸めを包む幅を求める
};

/// 世界の原点を基準にした倍精度の、座標軸に平行な直方体。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 大域の軸平行の直方体 {
    最小の端: [f64; 3],
    最大の端: [f64; 3],
}

impl 大域の軸平行の直方体 {
    /// 2つの位置に外接する箱。線分の覆いは線分の両端からこれで作る。
    pub fn 二点に外接する箱を求める(端: 大域ワールド位置, もう一方の端: 大域ワールド位置) -> Self {
        let 一方 = 成分を並べる(端);
        let 他方 = 成分を並べる(もう一方の端);
        Self {
            最小の端: [0usize, 1, 2].map(|軸| 一方[軸].min(他方[軸])),
            最大の端: [0usize, 1, 2].map(|軸| 一方[軸].max(他方[軸])),
        }
    }

    /// 端から、もう一方の端へ向かって比のぶんだけ進んだところまでを、進んだ先を求める丸めごと覆う箱。線分の覆いを、
    /// 見つけた当たりの時刻までへ切り詰めるのに使う。比は0以上1以下の無次元である。
    ///
    /// 注意: 進んだ先の成分は減算と積と和で1回ずつ丸まる。丸めが端を内側へ動かすと、真の端がチャンクの境界を踏む
    /// ところで未読込の隣のチャンクが覆いから外れ、完全でない覆いを完全と答える。それを防ぐため、端は誤差の上界の
    /// ぶんだけ外向きへ広げてある。上界の導出は`truncation_rounding_margin.rs`にある。
    pub fn 端から比のぶんだけ進んだところまでを丸めごと覆う箱を求める(
        端: 大域ワールド位置,
        もう一方の端: 大域ワールド位置,
        比: f64,
    ) -> Self {
        let 一方 = 成分を並べる(端);
        let 他方 = 成分を並べる(もう一方の端);
        let 進んだ先 = [0usize, 1, 2].map(|軸| 一方[軸] + (他方[軸] - 一方[軸]) * 比);
        Self {
            最小の端: [0usize, 1, 2].map(|軸| 一方[軸].min(進んだ先[軸])),
            最大の端: [0usize, 1, 2].map(|軸| 一方[軸].max(進んだ先[軸])),
        }
        .軸ごとの幅だけ端を外へ広げた箱を求める(線分の切り詰めが受ける丸めを包む幅を求める(一方, 他方))
    }

    /// 群のローカル空間の箱を、その群の大域原点を足して大域へ広げた箱。
    pub fn 局所の箱を大域原点から写して求める(
        大域原点: 大域ワールド位置, 局所の箱: &軸平行の直方体<ローカル>
    ) -> Self {
        let 原点 = 成分を並べる(大域原点);
        let 最小 = 単精度の成分を並べる(局所の箱.最小の端());
        let 最大 = 単精度の成分を並べる(局所の箱.最大の端());
        Self {
            最小の端: [0usize, 1, 2].map(|軸| 原点[軸] + f64::from(最小[軸].値())),
            最大の端: [0usize, 1, 2].map(|軸| 原点[軸] + f64::from(最大[軸].値())),
        }
    }

    /// 全方向へ同じ長さだけ広げた箱。カプセルの覆いは軸の両端の箱を半径ぶん広げて作る。
    ///
    /// 前提: 長さが0以上の有限値であること。負の長さを渡すと箱が裏返り、最小の端が最大の端を越える。
    pub fn 全方向へ広げた箱を求める(&self, 長さ: メートル) -> Self {
        let 幅 = f64::from(長さ.値());
        Self {
            最小の端: self.最小の端.map(|成分| 成分 - 幅),
            最大の端: self.最大の端.map(|成分| 成分 + 幅),
        }
    }

    /// 変位のぶんだけ平行移動させて掃いた範囲を包む箱。掃引の覆いは掃く前の箱からこれで作る。
    pub fn 変位で掃いた箱を求める(&self, 変位: 変位<ワールド>) -> Self {
        self.移動のぶんだけ掃いた箱を求める(軸ごとの移動を並べる(変位, 1.0))
    }

    /// 変位のうち先頭の比のぶんだけ平行移動させて掃いた範囲を、掃いた端を求める丸めごと覆う箱。掃引の覆いを、見つけた
    /// 接触の割合までへ切り詰めるのに使う。比は0以上1以下の無次元である。
    ///
    /// 注意: 掃いた端は比を掛ける積と端への和で1回ずつ丸まる。丸めが端を内側へ動かしたときの害と、それを防ぐために
    /// 端を外向きへ広げる幅は、線分の切り詰めと同じである。上界の導出は`truncation_rounding_margin.rs`にある。
    pub fn 変位の先頭の比のぶんだけ掃いた範囲を丸めごと覆う箱を求める(
        &self, 変位: 変位<ワールド>, 比: f64
    ) -> Self {
        let 移動 = 軸ごとの移動を並べる(変位, 比);
        let 幅 = 掃引の切り詰めが受ける丸めを包む幅を求める(self.最小の端, self.最大の端, 移動);
        self.移動のぶんだけ掃いた箱を求める(移動).軸ごとの幅だけ端を外へ広げた箱を求める(幅)
    }

    // 軸ごとの移動のぶんだけ平行移動させて掃いた範囲を包む箱。掃引の覆いと、その切り詰めが同じ形でここを通る。
    fn 移動のぶんだけ掃いた箱を求める(&self, 移動: [f64; 3]) -> Self {
        Self {
            最小の端: [0usize, 1, 2].map(|軸| self.最小の端[軸].min(self.最小の端[軸] + 移動[軸])),
            最大の端: [0usize, 1, 2].map(|軸| self.最大の端[軸].max(self.最大の端[軸] + 移動[軸])),
        }
    }

    // 軸ごとの幅だけ端を外側へ広げた箱。切り詰めの丸めを包むためにだけ使う。
    fn 軸ごとの幅だけ端を外へ広げた箱を求める(&self, 幅: [f64; 3]) -> Self {
        Self {
            最小の端: [0usize, 1, 2].map(|軸| self.最小の端[軸] - 幅[軸]),
            最大の端: [0usize, 1, 2].map(|軸| self.最大の端[軸] + 幅[軸]),
        }
    }

    /// 自分と相手が3軸すべてで重なるか。境界で触れるだけの場合も重なりとして数える。触れている形を落とさないためである。
    pub fn 相手と交わるか(&self, 相手: &Self) -> bool {
        (0usize..3).all(|軸| self.最小の端[軸] <= 相手.最大の端[軸] && 相手.最小の端[軸] <= self.最大の端[軸])
    }

    /// 成分ごとに小さいほうを集めた端。
    pub fn 最小の端(&self) -> 大域ワールド位置 {
        成分から組む(self.最小の端)
    }

    /// 成分ごとに大きいほうを集めた端。
    pub fn 最大の端(&self) -> 大域ワールド位置 {
        成分から組む(self.最大の端)
    }
}

// 大域の位置の3成分を軸の順に並べる。
fn 成分を並べる(位置: 大域ワールド位置) -> [f64; 3] {
    [位置.x().値(), 位置.y().値(), 位置.z().値()]
}

// 変位のうち先頭の比のぶんだけの移動を、軸の順に並べる。単精度から倍精度への変換は丸めを1つも通さない。
fn 軸ごとの移動を並べる(変位: 変位<ワールド>, 比: f64) -> [f64; 3] {
    [変位.x(), 変位.y(), 変位.z()].map(|成分| f64::from(成分.値()) * 比)
}

// 単精度の位置の3成分を軸の順に並べる。
fn 単精度の成分を並べる(端: 位置<ローカル>) -> [メートル; 3] {
    [端.x(), 端.y(), 端.z()]
}

// 軸の順に並んだ3成分を大域の位置へ戻す。
fn 成分から組む(成分: [f64; 3]) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(成分[0]),
        大域メートル::生成する(成分[1]),
        大域メートル::生成する(成分[2]),
    )
}
