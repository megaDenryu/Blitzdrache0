//! 大域の軸平行の直方体: 世界の原点を基準にした倍精度の、座標軸に平行な直方体である。
//!
//! 単精度の`軸平行の直方体`と別の型にするのは、世界の広がりが単精度の刻みで表せる範囲を越えるためである。
//! 問い合わせの覆いはプレイヤーの居る場所の大域の座標で来るため、その比較を単精度で行うと、原点から遠い場所で
//! 箱の端が実際の形の何倍もの幅で動く。
//!
//! 群のローカル空間の箱を、その群の大域原点を足してこの型へ広げる向きで比較を揃える。逆向き(覆いを単精度へ狭める)
//! にしないのは、狭める側に丸めが入り、覆いが実体より小さく出た場合に候補を落とすためである。単精度から倍精度へ
//! 広げる変換そのものは丸めを1つも通さない。端を動かすのは大域原点を足す加算だけである。
//!
//! ここに在るのは箱の代数だけである。2点への外接・畳み込み・包含・重なりはどれも成分の最小と最大を選ぶか端どうしを
//! 比べるかであり、端に丸めを1つも入れない。表面積は積と和を通すが、返すのは端ではなく数値であり、箱そのものを
//! 動かさない。端へ丸めを入れる操作、すなわち問い合わせの覆いを組む操作と局所の箱を大域へ写す操作は
//! `crates/blitz_collision/src/shape/global_box_cover.rs`が持つ。この分け方は局所座標の箱で先に採った形と同じである。
//! 参照: `crates/blitz_collision/src/shape/local_box_cover.rs`

use blitz_math::大域ワールド位置;

use super::global_box_components::{大域の位置の成分を軸の順に並べる, 軸の順の3成分から大域の位置を組む};

/// 世界の原点を基準にした倍精度の、座標軸に平行な直方体。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 大域の軸平行の直方体 {
    最小の端: [f64; 3],
    最大の端: [f64; 3],
}

impl 大域の軸平行の直方体 {
    /// 2つの位置に外接する箱。線分の覆いは線分の両端からこれで作る。成分の大小を選ぶだけで丸めを1つも通さない。
    pub fn 二点に外接する箱を求める(端: 大域ワールド位置, もう一方の端: 大域ワールド位置) -> Self {
        let 一方 = 大域の位置の成分を軸の順に並べる(端);
        let 他方 = 大域の位置の成分を軸の順に並べる(もう一方の端);
        Self {
            最小の端: [0usize, 1, 2].map(|軸| 一方[軸].min(他方[軸])),
            最大の端: [0usize, 1, 2].map(|軸| 一方[軸].max(他方[軸])),
        }
    }

    /// 自分と相手の両方を包む箱。動く形の木の内部節点の境界は、2つの子の箱をこれで畳んで作る。丸めを1つも通さない
    /// ため、節点が配下を包むことは演算の性質だけで言える。
    pub fn 相手を含む箱を求める(&self, 相手: &Self) -> Self {
        Self {
            最小の端: [0usize, 1, 2].map(|軸| self.最小の端[軸].min(相手.最小の端[軸])),
            最大の端: [0usize, 1, 2].map(|軸| self.最大の端[軸].max(相手.最大の端[軸])),
        }
    }

    /// 相手が自分の中へ丸ごと入るか。端が重なるだけの場合も入るものとして数える。動く形の索引は、実体の箱が
    /// ゆとり付きの箱の中に残っているかをこれで見て、残っていれば木を触らない。
    pub fn 相手を丸ごと含むか(&self, 相手: &Self) -> bool {
        (0usize..3).all(|軸| self.最小の端[軸] <= 相手.最小の端[軸] && 相手.最大の端[軸] <= self.最大の端[軸])
    }

    /// 自分と相手が3軸すべてで重なるか。境界で触れるだけの場合も重なりとして数える。触れている形を落とさないためである。
    pub fn 相手と交わるか(&self, 相手: &Self) -> bool {
        (0usize..3).all(|軸| self.最小の端[軸] <= 相手.最大の端[軸] && 相手.最小の端[軸] <= self.最大の端[軸])
    }

    /// 6つの面の面積の合計である平方メートル。動く形の木が葉を挿す先を選ぶとき、包む箱がどれだけ育つかの尺度に使う。
    /// 体積でなく表面積を使うのは、無作為な向きの線分が箱を貫く確率が表面積に比例するためである(凸体に対する
    /// 幾何確率の古典的な結果であり、光線追跡の階層で広く使われている)。
    pub fn 表面積の平方メートル(&self) -> f64 {
        let 辺 = [0usize, 1, 2].map(|軸| self.最大の端[軸] - self.最小の端[軸]);
        2.0 * (辺[0] * 辺[1] + 辺[1] * 辺[2] + 辺[2] * 辺[0])
    }

    /// 成分ごとに小さいほうを集めた端。
    pub fn 最小の端(&self) -> 大域ワールド位置 {
        軸の順の3成分から大域の位置を組む(self.最小の端)
    }

    /// 成分ごとに大きいほうを集めた端。
    pub fn 最大の端(&self) -> 大域ワールド位置 {
        軸の順の3成分から大域の位置を組む(self.最大の端)
    }

    pub(super) fn 軸の順に並べた両端を読む(&self) -> ([f64; 3], [f64; 3]) {
        (self.最小の端, self.最大の端)
    }

    pub(super) fn 軸の順に並べた両端から組む(最小の端: [f64; 3], 最大の端: [f64; 3]) -> Self {
        Self { 最小の端, 最大の端 }
    }
}
