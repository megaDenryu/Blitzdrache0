//! 大域の軸平行の直方体: 世界の原点を基準にした倍精度の、座標軸に平行な直方体である。
//!
//! 単精度の`軸平行の直方体`と別の型にするのは、世界の広がりが単精度の刻みで表せる範囲を越えるためである。
//! 問い合わせの覆いはプレイヤーの居る場所の大域の座標で来るため、その比較を単精度で行うと、原点から遠い場所で
//! 箱の端が実際の形の何倍もの幅で動く。
//!
//! 群のローカル空間の箱を、その群の大域原点を足してこの型へ広げる向きで比較を揃える。逆向き(覆いを単精度へ狭める)
//! にしないのは、狭める側に丸めが入り、覆いが実体より小さく出た場合に候補を落とすためである。単精度から倍精度へ
//! 広げる変換そのものは丸めを1つも通さない。端を動かすのは大域原点を足す加算だけである。
//!
//! 注意: 問い合わせの覆いを組む操作は、端を組む計算が入れる丸めを外から包む幅だけ端を外向きへ広げて返す。端が
//! 内側へ入った覆いは、真の端がチャンクの境界をちょうど踏むところで未読込の隣のチャンクを矩形から外し、完全でない
//! 覆いを完全と答えさせる。幅を操作1つずつに持たせるのは、覆いが完全性を偽らないことを端を組む工程の数に依らせない
//! ためである。同じ覆いを候補の列挙にも使うため、広げた端は候補を数件余計に挙げる側にだけ働く。局所の箱を大域原点
//! から写す操作も同じ幅を持つ。こちらの端が内側へ入る害は完全性の嘘ではなく、覆いに真に触れている子形状を候補から
//! 落とすことである。
//! 参照: `crates/blitz_collision/src/shape/cover_rounding_margin.rs`

use blitz_math::{メートル, ローカル, ワールド, 変位, 大域ワールド位置};

use super::axis_aligned_box::軸平行の直方体;
use super::cover_rounding_margin::{
    全方向へ広げた端が受ける丸めを包む幅を求める, 大域原点から写した端が受ける丸めを包む幅を求める, 掃いた端が受ける丸めを包む幅を求める,
    線分を比のぶんだけ進めた端が受ける丸めを包む幅を求める,
};
use super::global_box_components::{
    変位の先頭の比のぶんだけの移動を軸の順に並べる, 大域の位置の成分を軸の順に並べる, 局所の位置の成分を軸の順に並べる,
    軸の順の3成分から大域の位置を組む,
};

/// 世界の原点を基準にした倍精度の、座標軸に平行な直方体。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 大域の軸平行の直方体 {
    最小の端: [f64; 3],
    最大の端: [f64; 3],
}

impl 大域の軸平行の直方体 {
    /// 2つの位置に外接する箱。線分の覆いは線分の両端からこれで作る。成分の大小を選ぶだけで丸めを1つも通さない。
    pub fn 二点に外接する箱を求める(端: 大域ワールド位置, もう一方の端: 大域ワールド位置) -> Self {
        let 一方 = 大域の位置の成分を軸の順に並べる(端);
        let 他方 = 大域の位置の成分を軸の順に並べる(もう一方の端);
        Self {
            最小の端: [0usize, 1, 2].map(|軸| 一方[軸].min(他方[軸])),
            最大の端: [0usize, 1, 2].map(|軸| 一方[軸].max(他方[軸])),
        }
    }

    /// 端から、もう一方の端へ向かって比のぶんだけ進んだところまでを覆う箱。線分の覆いを、見つけた当たりの時刻まで
    /// へ切り詰めるのに使う。比は0以上1以下の無次元である。
    pub fn 端から比のぶんだけ進んだところまでを覆う箱を求める(
        端: 大域ワールド位置,
        もう一方の端: 大域ワールド位置,
        比: f64,
    ) -> Self {
        let 一方 = 大域の位置の成分を軸の順に並べる(端);
        let 他方 = 大域の位置の成分を軸の順に並べる(もう一方の端);
        let 進んだ先 = [0usize, 1, 2].map(|軸| 一方[軸] + (他方[軸] - 一方[軸]) * 比);
        Self {
            最小の端: [0usize, 1, 2].map(|軸| 一方[軸].min(進んだ先[軸])),
            最大の端: [0usize, 1, 2].map(|軸| 一方[軸].max(進んだ先[軸])),
        }
        .軸ごとの幅だけ端を外へ広げた箱を求める(線分を比のぶんだけ進めた端が受ける丸めを包む幅を求める(
            一方, 他方,
        ))
    }

    /// 群のローカル空間の箱を、その群の大域原点を足して大域へ広げた箱。原点を足す加算の丸めを包む幅だけ端を外へ
    /// 広げて返す。端が内側へ入った箱は、覆いに真に触れている子形状を候補から落とす。
    pub fn 局所の箱を大域原点から写して求める(
        大域原点: 大域ワールド位置, 局所の箱: &軸平行の直方体<ローカル>
    ) -> Self {
        let 原点 = 大域の位置の成分を軸の順に並べる(大域原点);
        let 最小 = 局所の位置の成分を軸の順に並べる(局所の箱.最小の端()).map(|成分| f64::from(成分.値()));
        let 最大 = 局所の位置の成分を軸の順に並べる(局所の箱.最大の端()).map(|成分| f64::from(成分.値()));
        Self {
            最小の端: [0usize, 1, 2].map(|軸| 原点[軸] + 最小[軸]),
            最大の端: [0usize, 1, 2].map(|軸| 原点[軸] + 最大[軸]),
        }
        .軸ごとの幅だけ端を外へ広げた箱を求める(大域原点から写した端が受ける丸めを包む幅を求める(原点, 最小, 最大))
    }

    /// 全方向へ同じ長さだけ広げた箱。カプセルの覆いは軸の両端の箱を半径ぶん広げて作る。
    ///
    /// 前提: 長さが0以上の有限値であること。負の長さを渡すと箱が裏返り、最小の端が最大の端を越える。
    pub fn 全方向へ広げた箱を求める(&self, 長さ: メートル) -> Self {
        let 幅 = f64::from(長さ.値());
        let 丸めを包む幅 = 全方向へ広げた端が受ける丸めを包む幅を求める(self.最小の端, self.最大の端, 幅);
        Self {
            最小の端: self.最小の端.map(|成分| 成分 - 幅),
            最大の端: self.最大の端.map(|成分| 成分 + 幅),
        }
        .軸ごとの幅だけ端を外へ広げた箱を求める(丸めを包む幅)
    }

    /// 変位のぶんだけ平行移動させて掃いた範囲を包む箱。掃引の覆いは掃く前の箱からこれで作る。
    pub fn 変位で掃いた箱を求める(&self, 変位: 変位<ワールド>) -> Self {
        self.移動のぶんだけ掃いた箱を求める(変位の先頭の比のぶんだけの移動を軸の順に並べる(変位, 1.0))
    }

    /// 変位のうち先頭の比のぶんだけ平行移動させて掃いた範囲を包む箱。掃引の覆いを、見つけた接触の割合までへ
    /// 切り詰めるのに使う。比は0以上1以下の無次元である。
    pub fn 変位の先頭の比のぶんだけ掃いた箱を求める(&self, 変位: 変位<ワールド>, 比: f64) -> Self {
        self.移動のぶんだけ掃いた箱を求める(変位の先頭の比のぶんだけの移動を軸の順に並べる(変位, 比))
    }

    // 軸ごとの移動のぶんだけ平行移動させて掃いた範囲を包む箱。掃引の覆いと、その切り詰めが同じ形でここを通る。
    fn 移動のぶんだけ掃いた箱を求める(&self, 移動: [f64; 3]) -> Self {
        let 丸めを包む幅 = 掃いた端が受ける丸めを包む幅を求める(self.最小の端, self.最大の端, 移動);
        Self {
            最小の端: [0usize, 1, 2].map(|軸| self.最小の端[軸].min(self.最小の端[軸] + 移動[軸])),
            最大の端: [0usize, 1, 2].map(|軸| self.最大の端[軸].max(self.最大の端[軸] + 移動[軸])),
        }
        .軸ごとの幅だけ端を外へ広げた箱を求める(丸めを包む幅)
    }

    // 軸ごとの幅だけ端を外側へ広げた箱。端を組む計算の丸めを包むためにだけ使う。
    fn 軸ごとの幅だけ端を外へ広げた箱を求める(&self, 幅: [f64; 3]) -> Self {
        Self {
            最小の端: [0usize, 1, 2].map(|軸| self.最小の端[軸] - 幅[軸]),
            最大の端: [0usize, 1, 2].map(|軸| self.最大の端[軸] + 幅[軸]),
        }
    }

    /// 自分と相手が3軸すべてで重なるか。境界で触れるだけの場合も重なりとして数える。触れている形を落とさないためである。
    pub fn 相手と交わるか(&self, 相手: &Self) -> bool {
        (0usize..3).all(|軸| self.最小の端[軸] <= 相手.最大の端[軸] && 相手.最小の端[軸] <= self.最大の端[軸])
    }

    /// 成分ごとに小さいほうを集めた端。
    pub fn 最小の端(&self) -> 大域ワールド位置 {
        軸の順の3成分から大域の位置を組む(self.最小の端)
    }

    /// 成分ごとに大きいほうを集めた端。
    pub fn 最大の端(&self) -> 大域ワールド位置 {
        軸の順の3成分から大域の位置を組む(self.最大の端)
    }
}
