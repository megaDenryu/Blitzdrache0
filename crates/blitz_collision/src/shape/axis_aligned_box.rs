//! 軸平行の直方体: 座標軸に平行な面だけを持つ直方体であり、成分ごとの最小の端と最大の端の対で表す。
//!
//! 姿勢の自由な形を包む粗い境界として使う。粗い境界が要るのは、詳細な判定が形の種類の組ごとに違う数学になるのに
//! 対し、包む箱どうしの重なりはどの形の組でも同じ3軸の比較で済むためである。空間索引の選別はこの比較だけで候補を
//! 絞り、絞った先で形ごとの数学へ入る。
//!
//! 型引数が端の住む座標系を表すのは、群のローカル空間の箱と別の空間の箱を取り違えても型が通る形にしないためである。
//! 標準トレイトを手で実装しているのは、導出が型引数`空間種`自身にも同じトレイトを要求するのに対し、`空間種`が
//! 実行時表現を持たない幻影型でその要求を満たせないためである(`blitz_math`の位置・変位が同じ形を持つ)。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断12: 空間探索は粗い候補選別と詳細判定を責務として分け、世界は二段構えで辿る」

use std::fmt;

use blitz_math::{メートル, 位置, 空間};

use super::error::{直方体の生成エラー, 軸名一覧};

/// 座標軸に平行な面だけを持つ直方体。
pub struct 軸平行の直方体<空間種> {
    最小の端: 位置<空間種>,
    最大の端: 位置<空間種>,
}

impl<空間種> 軸平行の直方体<空間種> {
    /// 成分ごとに小さいほうを集めた端。
    pub fn 最小の端(&self) -> 位置<空間種> {
        self.最小の端
    }

    /// 成分ごとに大きいほうを集めた端。
    pub fn 最大の端(&self) -> 位置<空間種> {
        self.最大の端
    }

    // 生成の検査に相当する保証を呼び出し側の算術が済ませている場合の入口。外接する箱の合成は、座標の上限から端が
    // 有限であることを、半分の長さが負でないことから最小の端が最大の端を越えないことを、それぞれ導いている。
    pub(super) fn 検査済みの端から組む(最小の端: 位置<空間種>, 最大の端: 位置<空間種>) -> Self {
        Self { 最小の端, 最大の端 }
    }
}

impl<空間種: 空間> 軸平行の直方体<空間種> {
    /// 端が有限であり、成分ごとに最小の端が最大の端以下であることを確かめて作る。
    pub fn 二つの端から生成する(
        最小の端: 位置<空間種>, 最大の端: 位置<空間種>
    ) -> Result<Self, 直方体の生成エラー> {
        let 最小 = 成分を並べる(最小の端);
        let 最大 = 成分を並べる(最大の端);
        for (軸, (小, 大)) in 軸名一覧.into_iter().zip(最小.into_iter().zip(最大)) {
            if !小.値().is_finite() || !大.値().is_finite() {
                return Err(直方体の生成エラー::箱の端が有限でない { 軸 });
            }
            if 小.値() > 大.値() {
                return Err(直方体の生成エラー::箱の最小が最大を越えている { 軸 });
            }
        }
        Ok(Self { 最小の端, 最大の端 })
    }

    /// 自分と相手の両方を包む箱。1つの衝突対象の外接は、子形状の箱をこの操作で畳んで作る。
    pub fn 相手を含む箱を求める(&self, 相手: &Self) -> Self {
        let 自分の最小 = 成分を並べる(self.最小の端);
        let 自分の最大 = 成分を並べる(self.最大の端);
        let 相手の最小 = 成分を並べる(相手.最小の端);
        let 相手の最大 = 成分を並べる(相手.最大の端);
        let 最小 = [0usize, 1, 2].map(|軸| メートル::生成する(自分の最小[軸].値().min(相手の最小[軸].値())));
        let 最大 = [0usize, 1, 2].map(|軸| メートル::生成する(自分の最大[軸].値().max(相手の最大[軸].値())));
        Self {
            最小の端: 位置::生成する(最小[0], 最小[1], 最小[2]),
            最大の端: 位置::生成する(最大[0], 最大[1], 最大[2]),
        }
    }
}

impl<空間種> Clone for 軸平行の直方体<空間種> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<空間種> Copy for 軸平行の直方体<空間種> {}

impl<空間種> PartialEq for 軸平行の直方体<空間種> {
    fn eq(&self, 相手: &Self) -> bool {
        self.最小の端 == 相手.最小の端 && self.最大の端 == 相手.最大の端
    }
}

impl<空間種> fmt::Debug for 軸平行の直方体<空間種> {
    fn fmt(&self, 出力: &mut fmt::Formatter<'_>) -> fmt::Result {
        出力
            .debug_struct("軸平行の直方体")
            .field("最小の端", &self.最小の端)
            .field("最大の端", &self.最大の端)
            .finish()
    }
}

// 3軸の成分を軸の順に並べる。軸ごとに同じ手順を回す操作がこれを通して読む。
fn 成分を並べる<空間種: 空間>(端: 位置<空間種>) -> [メートル; 3] {
    [端.x(), 端.y(), 端.z()]
}
