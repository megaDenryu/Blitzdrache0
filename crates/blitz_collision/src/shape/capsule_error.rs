//! カプセルを作るときに破れる条件。
//!
//! 形の局所座標の生成エラーと別の型にするのは、あちらが位置と変位の成分そのものの破れを言うのに対し、こちらは
//! カプセルの半径というこの形だけが持つ量の破れを言うためである。軸の両端と掃引の変位の破れはあちらが持つ。

use thiserror::Error;

use super::coordinate_limit::形状の座標の絶対値の上限メートル;

/// カプセルの生成が拒否する理由。掃引の変位を添えたカプセルの生成もこの型で拒む。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum カプセルの生成エラー {
    /// カプセルの半径が0以下か、有限でない値だった。
    #[error("カプセルの半径が正の有限値でない")]
    カプセルの半径が正の有限値でない,
    /// カプセルの半径が、係数の桁あふれを避けるために課した座標の絶対値の上限を越えていた。
    #[error("カプセルの半径が形の座標の絶対値の上限{}メートルを越えている", 形状の座標の絶対値の上限メートル)]
    カプセルの半径が上限を越えている,
}
