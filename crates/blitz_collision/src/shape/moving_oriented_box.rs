//! 動く任意姿勢の直方体: 直方体そのものと、1つの刻みでそれを平行移動させる変位を1つにまとめて持つ。
//!
//! 形と動きを1つの型にまとめる理由は`形を掃引するカプセル`と同じである。動く形どうしの接触が答えるのは
//! 「この2つの形をそれぞれの変位だけ動かすとどこで出会うか」という1つの問いであり、形だけでも変位だけでも
//! 問いにならない。2つを別々の引数で受けると、対の片側の形にもう片側の変位を渡す取り違えが型を通ってしまう。
//!
//! 回転は持たない。動く形どうしの接触が扱うのは平行移動する形の対だけであり、回転を含む連続衝突は能力の目録に
//! 残したまま作っていないためである。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断13: 連続衝突と接触点集合を能力として最初から見据える」

use super::local_displacement::形の局所座標の変位;
use super::oriented_box::任意姿勢の直方体;

/// 平行移動する任意姿勢の直方体。形そのものと、1つの刻みでそれを動かす変位を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 動く任意姿勢の直方体 {
    直方体: 任意姿勢の直方体,
    平行移動の変位: 形の局所座標の変位,
}

impl 動く任意姿勢の直方体 {
    /// 形と変位を組にする。どちらも自分の型が不変条件を守るため、この生成に検査は無い。
    pub fn 生成する(直方体: 任意姿勢の直方体, 平行移動の変位: 形の局所座標の変位) -> Self {
        Self {
            直方体, 平行移動の変位
        }
    }

    /// 刻みの始まりの姿勢での直方体。
    pub fn 直方体(&self) -> 任意姿勢の直方体 {
        self.直方体
    }

    /// 1つの刻みでこの直方体を動かす変位。
    pub fn 平行移動の変位(&self) -> 形の局所座標の変位 {
        self.平行移動の変位
    }
}
