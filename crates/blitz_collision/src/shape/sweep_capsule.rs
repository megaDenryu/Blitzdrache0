//! 形を掃引するカプセル: カプセルを、指定した変位だけ平行移動させる掃引そのものである。形そのものと動きを
//! 1つの型にまとめるのは、問い合わせが答えるのが「この形をこの変位だけ動かすとどこまで動けるか」という1つの
//! 問いであり、片方だけでは問いにならないためである。
//!
//! 形そのものは`カプセル`が持ち、この型はそれと掃引の変位を保持する。半径の検査も軸の読み取りもカプセルの側に
//! あるため、この型に検査は無い。掃引の変位は有限性と成分の絶対値の上限を変位の型が守る。
//!
//! 形の種類ごとに別の型を置かないのは、三角形への掃引も任意姿勢の直方体への掃引も、同じ局所座標系の同じ4つの
//! 値を受け取り、同じ不変条件を守り、同じ操作だけを持つためである。理由も置き場の選び方も
//! `crates/blitz_collision/src/shape/shape_segment.rs` に書いたものと同じである。

use super::capsule::カプセル;
use super::capsule_error::カプセルの生成エラー;
use super::local_displacement::形の局所座標の変位;
use super::local_position::形の局所座標の位置;

/// 形を掃引するカプセル。カプセルの形と、それを動かす変位を1つにまとめて持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 形を掃引するカプセル {
    カプセル: カプセル,
    掃引の変位: 形の局所座標の変位,
}

impl 形を掃引するカプセル {
    /// 軸の両端と半径からカプセルを組み、掃引の変位を添える。半径の条件はカプセルの生成が確かめる。
    pub fn 生成する(
        軸の始点: 形の局所座標の位置,
        軸の終点: 形の局所座標の位置,
        半径のメートル: f64,
        掃引の変位: 形の局所座標の変位,
    ) -> Result<Self, カプセルの生成エラー> {
        Ok(Self {
            カプセル: カプセル::生成する(軸の始点, 軸の終点, 半径のメートル)?,
            掃引の変位,
        })
    }

    /// 掃引の始まりの姿勢での軸の始点。
    pub fn 軸の始点(&self) -> 形の局所座標の位置 {
        self.カプセル.軸の始点()
    }

    /// 掃引の始まりの姿勢での軸の終点。
    pub fn 軸の終点(&self) -> 形の局所座標の位置 {
        self.カプセル.軸の終点()
    }

    /// 軸から測ったカプセルの半径であるメートル。
    pub fn 半径のメートル(&self) -> f64 {
        self.カプセル.半径のメートル()
    }

    /// カプセル全体を動かそうとする変位。
    pub fn 掃引の変位(&self) -> 形の局所座標の変位 {
        self.掃引の変位
    }

    /// 掃引の始まりの姿勢での形そのもの。動くカプセルどうしの接触が、片方を静止させるときに読む。
    pub fn 動きを取り去ったカプセルを求める(&self) -> カプセル {
        self.カプセル
    }

    /// 形と半径をそのままに、掃引の変位だけを差し替えたカプセル。相対運動への還元が、動く相手を静止させた
    /// 掃引を組むときに読む。形が変わらないため半径の検査を通し直す必要が無い。
    pub fn 掃引の変位を差し替えたカプセルを求める(&self, 掃引の変位: 形の局所座標の変位) -> Self {
        Self {
            カプセル: self.カプセル,
            掃引の変位,
        }
    }

    // 軸の始点から終点へ向かう変位。長さ0の軸(球)も許すため、この変位は零になりうる。
    pub(crate) fn 軸の変位を求める(&self) -> 形の局所座標の変位 {
        self.カプセル.軸の変位を求める()
    }

    // 掃引の始まりの姿勢での軸の2つの端点。並びは始点・終点であり、求解はこの順に候補を数える。
    pub(crate) fn 軸の端点を並べる(&self) -> [形の局所座標の位置; 2] {
        self.カプセル.軸の端点を並べる()
    }
}
