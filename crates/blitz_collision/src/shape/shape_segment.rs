//! 形を貫く線分: 形に当たるかを問い合わせる、始点と終点で決まる線分である。
//! 半直線でも直線でもなく線分であるのは、利用者(視点と注視点の間の遮蔽、次の刻みまでの移動)が
//! どちらの端も持っているためである。
//!
//! 端点が有限でありその絶対値が上限に収まることは`形の局所座標の位置`の生成が保証するため、この型は検査を持たない。
//!
//! 形の種類ごとに別の型を置かないのは、三角形への問い合わせも任意姿勢の直方体への問い合わせも、同じ局所座標系の
//! 同じ2つの端点を受け取り、同じ不変条件を守り、同じ操作(端の読み取り・始点から終点への変位・媒介変数が指す点)
//! だけを持つためである。形ごとに写した型は、片方だけを直した食い違いが答えの違いとして出るまで見つからない。
//!
//! 高さ場を貫く線分(`crates/blitz_collision/src/height_field`)はここに畳まない。あちらは端点を格子原点を基準に
//! した型で持ち、成分の意味も、成分の絶対値へ課す上限の根拠も違うためである。
//!
//! `crate::shape`へ置くのは、判断5が挙げた形状の目録に線分そのものが載っており、この型が形の局所座標系に住む
//! 形だからである。`crate::solver`へ置かないのは、あちらが答えの側の量(媒介変数・割合)と求解の道具を持つ場所で
//! あり、問い合わせの入力になる形を持つ場所ではないためである。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断5: 形状の目録を先に確定する(物理形状と描画形状は別物)」

use crate::solver::線分の媒介変数;

use super::local_displacement::形の局所座標の変位;
use super::local_error::形の局所座標の生成エラー;
use super::local_position::形の局所座標の位置;

/// 形に当たるかを問い合わせる、始点と終点で決まる線分。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 形を貫く線分 {
    始点: 形の局所座標の位置,
    終点: 形の局所座標の位置,
}

impl 形を貫く線分 {
    /// 始点と終点から作る。端点の有限性と成分の絶対値の上限は位置の型が守るため、この生成に検査は無い。
    pub fn 生成する(始点: 形の局所座標の位置, 終点: 形の局所座標の位置) -> Self {
        Self { 始点, 終点 }
    }

    /// 線分の媒介変数が0の端。
    pub fn 始点(&self) -> 形の局所座標の位置 {
        self.始点
    }

    /// 線分の媒介変数が1の端。
    pub fn 終点(&self) -> 形の局所座標の位置 {
        self.終点
    }

    /// 始点から終点へ向かう変位。媒介変数が1増えるあいだに進む量である。
    pub fn 始点から終点への変位を求める(&self) -> 形の局所座標の変位 {
        self.始点.終点までの変位を求める(self.終点)
    }

    /// 媒介変数で指し示す線分上の点。始点へ変位の実数倍を足して求めるため、媒介変数が0の端は始点そのものになる。
    /// 端点が有限でも成分の差が浮動小数点の表せる範囲を越えうるため、有限性の検査を通し直す。
    pub fn 線分上の点を求める(
        &self, 媒介変数: 線分の媒介変数
    ) -> Result<形の局所座標の位置, 形の局所座標の生成エラー> {
        self.始点
            .変位だけ進んだ位置を求める(self.始点から終点への変位を求める().実数倍する(媒介変数.値()))
    }
}
