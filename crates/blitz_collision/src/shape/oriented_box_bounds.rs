//! 任意姿勢の直方体から、それを包む軸平行の直方体を合成する工程。
//!
//! 呼び出しタイミング: 世界の側が形を読み込んだときの1回だけである。問い合わせのたびには呼ばない。選別は1フレームに
//! 何度も走るのに対し、形そのものは読込から解除まで動かないためである。
//!
//! 合成の数学は「中心 ± 回転行列の成分の絶対値と軸ごとの半分の長さの積の和」である。回転行列の列は、直方体自身の
//! 軸の向きを群のローカル空間で表したものであるから、軸に沿った半分の長さの変位を回して成分の絶対値を取り、
//! 3軸ぶん足せば同じ量になる。行列を組み立てずにこの形で書くのは、回転が四元数として在り、行列へ直す経路をここで
//! 新しく作らないためである。
//!
//! 端へ余白を足す理由と幅の根拠は `crates/blitz_collision/src/shape/coordinate_limit.rs` にある。
//! 端が有限であり最小が最大を越えないことは同じ上限の算術が保証するため、検査済みの入口から組む。

use blitz_math::{ローカル, メートル, 位置, 変位};

use super::axis_aligned_box::軸平行の直方体;
use super::coordinate_limit::外接する箱の余白の相対量;
use super::oriented_box::任意姿勢の直方体;

impl 任意姿勢の直方体 {
    /// この直方体を包む、群のローカル空間で軸平行の直方体。丸めで実体より小さく出ないよう端の外側へ余白を足すため、
    /// 最小の外接そのものではなく、それをわずかに広げた箱である。
    pub fn 外接する軸平行の直方体を求める(&self) -> 軸平行の直方体<ローカル> {
        let 中心 = [self.中心().x(), self.中心().y(), self.中心().z()];
        let 広がり = self.回転で写した軸ごとの広がりを求める();
        let 余白 = [0usize, 1, 2].map(|軸| (中心[軸].値().abs() + 広がり[軸].値()) * 外接する箱の余白の相対量);
        let 最小 = [0usize, 1, 2].map(|軸| メートル::生成する(中心[軸].値() - 広がり[軸].値() - 余白[軸]));
        let 最大 = [0usize, 1, 2].map(|軸| メートル::生成する(中心[軸].値() + 広がり[軸].値() + 余白[軸]));
        軸平行の直方体::検査済みの端から組む(
            位置::生成する(最小[0], 最小[1], 最小[2]),
            位置::生成する(最大[0], 最大[1], 最大[2]),
        )
    }

    // 直方体自身の3軸に沿った半分の長さを群のローカル空間へ回し、軸ごとに成分の絶対値を足し合わせた広がり。
    fn 回転で写した軸ごとの広がりを求める(&self) -> [メートル; 3] {
        let 半分 = self.軸ごとの半分の長さ().成分を並べる();
        let 回した軸 = [0usize, 1, 2].map(|軸| self.回転().変位を回す(軸に沿った変位を組む(軸, 半分[軸])));
        let 成分の絶対値 =
            回した軸.map(|変位| [変位.x().値().abs(), 変位.y().値().abs(), 変位.z().値().abs()]);
        [0usize, 1, 2]
            .map(|成分| メートル::生成する(成分の絶対値[0][成分] + 成分の絶対値[1][成分] + 成分の絶対値[2][成分]))
    }
}

// 指定した軸だけに長さを持つ、直方体自身の座標系での変位。
fn 軸に沿った変位を組む(軸: usize, 長さ: メートル) -> 変位<ローカル> {
    let mut 成分 = [メートル::生成する(0.0); 3];
    成分[軸] = 長さ;
    位置::<ローカル>::生成する(成分[0], 成分[1], 成分[2]).原点からの変位()
}
