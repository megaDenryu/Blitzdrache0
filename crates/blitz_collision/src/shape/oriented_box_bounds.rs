//! 任意姿勢の直方体から、それを包む軸平行の直方体を合成する工程。
//!
//! 呼び出しタイミング: 呼び出し側が形を1つ受け取ったときの1回だけである。合成した箱は呼び出し側が保持し、問い合わせの
//! たびには合成し直さない。粗い選別は1つの形に対して何度も走るのに対し、形そのものは寿命の間ずっと動かないためである。
//!
//! 合成の数学は「中心 ± 直方体自身の軸の成分の絶対値と軸ごとの半分の長さの積の和」である。軸は、直方体自身の
//! 軸の向きをその直方体が住む座標系で表したものであるから、軸に沿った半分の長さの変位を回して成分の絶対値を
//! 取り、3軸ぶん足せば同じ量になる。
//!
//! 積和を倍精度で組み立てるのは、単精度で組むと丸めの絶対誤差が半分の長さに比例して残り、真の広がりがそれより
//! はるかに小さい姿勢(長い半軸がほぼ直交へ回った箱)で結果が誤差に埋もれるためである。中心と軸を倍精度で読み直す
//! のは`oriented_box_double.rs`であり、詳細判定も同じ読み直しを通る。端を単精度へ戻すときの丸めは外向きに
//! 固定する(`outward_narrowing.rs`)。
//!
//! 端へ余白を足す理由と幅の根拠は `crates/blitz_collision/src/shape/coordinate_limit.rs` にある。端が有限であり
//! 最小が最大を越えないことは同じ上限の算術が保証するため、検査済みの入口から組む。

use blitz_math::{メートル, ローカル, 位置};

use super::axis_aligned_box::軸平行の直方体;
use super::box_axis::直方体自身の座標軸;
use super::coordinate_limit::外接する箱の余白の相対量;
use super::oriented_box::任意姿勢の直方体;
use super::oriented_box_double::任意姿勢の直方体の倍精度の幾何;
use super::outward_narrowing::{
    倍精度の値を大きい側へ丸めて単精度へ狭める, 倍精度の値を小さい側へ丸めて単精度へ狭める
};

impl 任意姿勢の直方体 {
    /// この直方体を包む、同じ局所座標系で軸平行の直方体。丸めで実体より小さく出ないよう端の外側へ余白を足すため、
    /// 最小の外接そのものではなく、それをわずかに広げた箱である。
    pub fn 外接する軸平行の直方体を求める(&self) -> 軸平行の直方体<ローカル> {
        let 幾何 = 任意姿勢の直方体の倍精度の幾何::直方体から組む(self);
        let 中心 = [幾何.中心().xのメートル(), 幾何.中心().yのメートル(), 幾何.中心().zのメートル()];
        let 広がり = 軸ごとの広がりを求める(&幾何);
        let 半分の長さの総和 = 幾何.半分の長さを並べる().into_iter().sum::<f64>();
        let 余白 = [0usize, 1, 2].map(|軸| (中心[軸].abs() + 半分の長さの総和) * f64::from(外接する箱の余白の相対量));
        let 最小 = [0usize, 1, 2].map(|軸| {
            メートル::生成する(倍精度の値を小さい側へ丸めて単精度へ狭める(
                中心[軸] - 広がり[軸] - 余白[軸],
            ))
        });
        let 最大 = [0usize, 1, 2].map(|軸| {
            メートル::生成する(倍精度の値を大きい側へ丸めて単精度へ狭める(
                中心[軸] + 広がり[軸] + 余白[軸],
            ))
        });
        軸平行の直方体::検査済みの端から組む(位置::生成する(最小[0], 最小[1], 最小[2]), 位置::生成する(最大[0], 最大[1], 最大[2]))
    }
}

// 直方体自身の3軸に沿った半分の長さを局所座標系へ回し、成分ごとに絶対値を足し合わせた広がり。
fn 軸ごとの広がりを求める(幾何: &任意姿勢の直方体の倍精度の幾何) -> [f64; 3] {
    let 半分 = 幾何.半分の長さを並べる();
    let 軸 = 直方体自身の座標軸::並べる().map(|軸| {
        let 向き = 幾何.軸に沿った単位向き(軸);
        [向き.xのメートル(), 向き.yのメートル(), 向き.zのメートル()]
    });
    [0usize, 1, 2].map(|成分| 軸[0][成分].abs() * 半分[0] + 軸[1][成分].abs() * 半分[1] + 軸[2][成分].abs() * 半分[2])
}
