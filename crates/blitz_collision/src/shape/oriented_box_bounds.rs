//! 任意姿勢の直方体から、それを包む軸平行の直方体を合成する工程。
//!
//! 呼び出しタイミング: 呼び出し側が形を1つ受け取ったときの1回だけである。合成した箱は呼び出し側が保持し、問い合わせの
//! たびには合成し直さない。粗い選別は1つの形に対して何度も走るのに対し、形そのものは寿命の間ずっと動かないためである。
//!
//! 合成の数学は「中心 ± 回転行列の成分の絶対値と軸ごとの半分の長さの積の和」である。回転行列の列は、直方体自身の
//! 軸の向きをその直方体が住む座標系で表したものであるから、軸に沿った半分の長さの変位を回して成分の絶対値を取り、
//! 3軸ぶん足せば同じ量になる。
//!
//! 積和を倍精度で組み立てるのは、単精度で組むと丸めの絶対誤差が半分の長さに比例して残り、真の広がりがそれより
//! はるかに小さい姿勢(長い半軸がほぼ直交へ回った箱)で結果が誤差に埋もれるためである。四元数を倍精度で正規化して
//! から回転行列の成分を組むため、外部の四元数の実装が単精度で行う回転の適用にこの合成は依存しない。端を単精度へ
//! 戻すときの丸めは外向きに固定する(`outward_narrowing.rs`)。
//!
//! 端へ余白を足す理由と幅の根拠は `crates/blitz_collision/src/shape/coordinate_limit.rs` にある。端が有限であり
//! 最小が最大を越えないことは同じ上限の算術が保証するため、検査済みの入口から組む。

use blitz_math::{クォータニオン, メートル, ローカル, 位置};

use super::axis_aligned_box::軸平行の直方体;
use super::coordinate_limit::外接する箱の余白の相対量;
use super::oriented_box::任意姿勢の直方体;
use super::outward_narrowing::{
    倍精度の値を大きい側へ丸めて単精度へ狭める, 倍精度の値を小さい側へ丸めて単精度へ狭める
};

impl 任意姿勢の直方体 {
    /// この直方体を包む、同じ局所座標系で軸平行の直方体。丸めで実体より小さく出ないよう端の外側へ余白を足すため、
    /// 最小の外接そのものではなく、それをわずかに広げた箱である。
    pub fn 外接する軸平行の直方体を求める(&self) -> 軸平行の直方体<ローカル> {
        let 中心 = [self.中心().x(), self.中心().y(), self.中心().z()].map(|成分| f64::from(成分.値()));
        let 広がり = self.回転で写した軸ごとの広がりを求める();
        let 半分の長さの総和 = self.軸ごとの半分の長さの総和を求める();
        let 余白 = [0usize, 1, 2].map(|軸| (中心[軸].abs() + 半分の長さの総和) * f64::from(外接する箱の余白の相対量));
        let 最小 = [0usize, 1, 2].map(|軸| {
            メートル::生成する(倍精度の値を小さい側へ丸めて単精度へ狭める(
                中心[軸] - 広がり[軸] - 余白[軸],
            ))
        });
        let 最大 = [0usize, 1, 2].map(|軸| {
            メートル::生成する(倍精度の値を大きい側へ丸めて単精度へ狭める(
                中心[軸] + 広がり[軸] + 余白[軸],
            ))
        });
        軸平行の直方体::検査済みの端から組む(位置::生成する(最小[0], 最小[1], 最小[2]), 位置::生成する(最大[0], 最大[1], 最大[2]))
    }

    // 直方体自身の3軸に沿った半分の長さを局所座標系へ回し、軸ごとに成分の絶対値を足し合わせた広がり。
    fn 回転で写した軸ごとの広がりを求める(&self) -> [f64; 3] {
        let 半分 = self.倍精度の軸ごとの半分の長さを並べる();
        let 行列 = 倍精度で正規化した四元数から回転行列を組む(self.回転());
        [0usize, 1, 2].map(|軸| 行列[軸][0].abs() * 半分[0] + 行列[軸][1].abs() * 半分[1] + 行列[軸][2].abs() * 半分[2])
    }

    // 余白の基準になる量。どの軸へ回っても広がりはこの値を越えないため、丸めの絶対誤差の上界の尺度になる。
    fn 軸ごとの半分の長さの総和を求める(&self) -> f64 {
        let 半分 = self.倍精度の軸ごとの半分の長さを並べる();
        半分[0] + 半分[1] + 半分[2]
    }

    fn 倍精度の軸ごとの半分の長さを並べる(&self) -> [f64; 3] {
        self.軸ごとの半分の長さ().成分を並べる().map(|長さ| f64::from(長さ.値()))
    }
}

// 四元数の4成分を倍精度へ広げ、長さで割ってから回転行列の成分を組む。単精度で正規化された四元数の長さは倍精度で
// 見ると1から単精度の刻みぶん離れており、そのずれは行列の成分を通って半分の長さに比例した誤差になる。ここで割れば
// 残るのは倍精度の丸めだけになる。長さが零にならないことは四元数の型が不変条件として保証する。
fn 倍精度で正規化した四元数から回転行列を組む(回転: クォータニオン<ローカル, ローカル>) -> [[f64; 3]; 3] {
    let [生のx, 生のy, 生のz, 生のw] = 回転.境界用xyzw配列().map(f64::from);
    let 長さ = (生のx * 生のx + 生のy * 生のy + 生のz * 生のz + 生のw * 生のw).sqrt();
    let (x, y, z, w) = (生のx / 長さ, 生のy / 長さ, 生のz / 長さ, 生のw / 長さ);
    [
        [1.0 - 2.0 * (y * y + z * z), 2.0 * (x * y - z * w), 2.0 * (x * z + y * w)],
        [2.0 * (x * y + z * w), 1.0 - 2.0 * (x * x + z * z), 2.0 * (y * z - x * w)],
        [2.0 * (x * z - y * w), 2.0 * (y * z + x * w), 1.0 - 2.0 * (x * x + y * y)],
    ]
}
