//! 直方体の軸ごとの半分の長さの生成が、どの組を拒みどの組を受け入れるかの反証。
//!
//! 拒む側と受け入れる側を同じところへ置くのは、境目が「0である軸の数」という1つの数で決まるためである。
//! 片方だけを反証にすると、板を拒むまで検査を厳しくした変更も、線分を受け入れるまで緩めた変更も通ってしまう。

#![cfg(test)]

use blitz_math::メートル;

use super::error::直方体の生成エラー;
use super::half_extent::直方体の軸ごとの半分の長さ;

fn 半分の長さを組む(成分: [f32; 3]) -> Result<直方体の軸ごとの半分の長さ, 直方体の生成エラー> {
    直方体の軸ごとの半分の長さ::生成する(成分.map(メートル::生成する))
}

#[test]
fn 半分の長さが負なら拒む() {
    assert_eq!(
        半分の長さを組む([1.0, -0.1, 1.0]),
        Err(直方体の生成エラー::半分の長さが負か非有限 { 軸: "Y" }),
        "面が裏返る負の半分の長さが受け入れられた"
    );
}

/// 0が高々1軸なら厚みの無い板であり、据えた部品としてありうるため受け入れる。
#[test]
fn 厚みの無い板は受け入れる() {
    assert!(半分の長さを組む([1.0, 0.0, 1.0]).is_ok(), "厚みの無い板が拒まれた");
}

/// 2軸以上が0の組は線分か点へ退化しており、面を持たないため接触点集合が同じ位置の接触点を重ねて作る。
#[test]
fn 線分と点へ退化した半分の長さは拒む() {
    assert_eq!(
        半分の長さを組む([1.0, 0.0, 0.0]),
        Err(直方体の生成エラー::半分の長さが2軸以上で零),
        "2軸が0の線分が直方体として受け入れられた"
    );
    assert_eq!(
        半分の長さを組む([0.0; 3]),
        Err(直方体の生成エラー::半分の長さが2軸以上で零),
        "3軸が0の点が直方体として受け入れられた"
    );
}
