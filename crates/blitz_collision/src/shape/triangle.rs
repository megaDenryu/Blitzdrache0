//! 局所座標の三角形: 3つの頂点の位置だけで表す、姿勢にも並びにも制約の無い三角形である。
//!
//! 高さ場の三角形(`crates/blitz_collision/src/height_field/capsule_sweep/surface_triangle.rs`)と別の型に
//! するのは、あちらが升目の四隅の高さから組み立てられ、格子の添字と隅の名前を持つためである。こちらは
//! 頂点の位置しか持たず、どの升目にも属さない。
//!
//! 頂点の並びが面の向きを決める。第1から第2へ向かう変位と第1から第3へ向かう変位の外積が、面に垂直な向きで
//! ある。この向きを「表」と呼ぶかどうかはこの型が決めない。表裏性は衝突形状が宣言する属性であり、
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断10: 衝突形状が宣言できる属性」。
//!
//! 面積が零の三角形(3点が一直線に並ぶか重なる場合)も値としては作れる。拒むのは、面の向きが要る問い合わせを
//! 組む地点である。値の生成で拒まないのは、頂点の列を読み込む側が退化した組を見つけて取り除けるようにするためである。

use super::local_displacement::形の局所座標の変位;
use super::local_position::形の局所座標の位置;
use super::triangle_vertex_number::三角形の頂点の番号;

/// 3つの頂点の位置で表す三角形。頂点の並びが面に垂直な向きを決める。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 局所座標の三角形 {
    頂点の位置: [形の局所座標の位置; 3],
}

impl 局所座標の三角形 {
    /// 3つの頂点から作る。頂点の有限性と成分の絶対値の上限は位置の型が守るため、この生成に検査は無い。
    pub fn 三つの頂点から生成する(頂点の位置: [形の局所座標の位置; 3]) -> Self {
        Self { 頂点の位置 }
    }

    /// 番号が指す頂点の位置。
    pub fn 頂点の位置(&self, 番号: 三角形の頂点の番号) -> 形の局所座標の位置 {
        self.頂点の位置[番号.並びの位置()]
    }

    /// 番号の頂点から次の番号の頂点へ向かう変位。3つの番号でこの三角形の3辺が尽きる。
    pub fn 辺の変位を求める(&self, 始まりの頂点: 三角形の頂点の番号) -> 形の局所座標の変位 {
        self.頂点の位置(始まりの頂点)
            .終点までの変位を求める(self.頂点の位置(始まりの頂点.次の頂点()))
    }

    /// 面に垂直な変位。長さは三角形の面積の2倍であり、1に正していない。向きは頂点の並びが決める。
    pub fn 面に垂直な変位を求める(&self) -> 形の局所座標の変位 {
        let 第1から第2へ = self.辺の変位を求める(三角形の頂点の番号::第1の頂点);
        let 第1から第3へ = self
            .頂点の位置(三角形の頂点の番号::第1の頂点)
            .終点までの変位を求める(self.頂点の位置(三角形の頂点の番号::第3の頂点));
        第1から第2へ.外積(第1から第3へ)
    }

    /// 面積が零であるか。3点が一直線に並ぶか重なる三角形と、外積が零へ落ちるほど細く小さい三角形が該当する。
    pub fn 面積が零か(&self) -> bool {
        let 長さの二乗 = self.面に垂直な変位を求める().長さの二乗();
        !長さの二乗.is_finite() || 長さの二乗 <= 0.0
    }

    /// 面に垂直な変位を長さ1に正したもの。面積が零で向きが定まらない三角形では値なしを返す。
    pub fn 面の単位法線の変位を求める(&self) -> Option<形の局所座標の変位> {
        if self.面積が零か() {
            return None;
        }
        let 垂直な変位 = self.面に垂直な変位を求める();
        Some(垂直な変位.実数倍する(1.0 / 垂直な変位.長さの二乗().sqrt()))
    }
}
