//! 箱の端を組む計算が端へ入れる丸めを、外から包む幅。受け取るのは端を組む演算に入る値、返すのは軸ごとの幅である。
//! 幅を足し引きするのは`global_axis_aligned_box.rs`が端を組む5つの操作、すなわち半径ぶん広げる操作・変位で掃く
//! 操作・線分を当たりの時刻まで切り詰める操作・掃引を接触の割合まで切り詰める操作・局所の箱を大域原点から写す操作
//! である。前の4つは問い合わせの覆いを組み、最後の1つは覆いと突き合わせる子形状の箱を組む。形の内側の空間索引が
//! 使う`local_box_cover.rs`の2つの操作(半径ぶん広げる操作・変位で掃く操作)も、同じ導出の幅を同じ理由で足す。
//!
//! 幅が要るのは、箱の端が真の端の外側に在ることを、操作1つの中で閉じた不変条件にするためである。覆いの側で端が
//! 内側へ入ると、その覆いをチャンクの座標へ写したとき、真の端がチャンクの境界をちょうど踏むところで未読込の隣の
//! チャンクが矩形から外れうる。外れた矩形は読込済みのチャンクだけで埋まり、覆いは「対象範囲を完全に評価できた」と
//! 答える。その答えは見つけた当たりを確定として返してよいという判断へそのまま渡るため、確定でない当たりを確定と
//! 言う誤りになる。これは詳細判定でも取り返せない。
//!
//! 子形状の箱の側で端が内側へ入る害は、完全性の嘘ではなく候補の取りこぼしである。覆いに真に触れている子形状の
//! 箱の端が内側へ落ちると、その子形状は候補に挙がらず詳細判定へ渡らない。当たりが在るのに無いと答えるこの誤りも、
//! 後の工程で取り返せない点で同じ重さである。
//!
//! 丸めが1回で済む端では、この誤りは起こらない。チャンクの境界は倍精度でちょうど表せる値であり、最近接への丸めは
//! 境界以上の実数を境界より小さい倍精度へは動かさないためである。丸めが2回続く端(半径ぶん広げてから掃いた端)でも、
//! 2回ぶんの誤差の上限は境界のすぐ下の刻み1つとちょうど等しく、等号が成る唯一の場合は偶数への丸めが境界の側を
//! 選ぶため、やはり起こらない。それでも幅を足すのは、この安全が丸めの回数と境界の2進表現に依存した性質であり、
//! 端を組む工程を1つ足しただけで崩れるためである。実際、丸めが3回になる切り詰めでは境界をまたぐ入力が現に在る。
//! 工程ごとに端を外側へ置けば、覆いが完全性を偽らないことは工程の数に依らない。
//!
//! 写す側の取りこぼしも、現には起こせない。突き合わせる相手は覆いの端そのもの、すなわち倍精度の値であり、写す加算は
//! 丸めを1回しか通らない。最近接への丸めは、ある倍精度の値以上の実数をその値より小さい倍精度へは動かさないから、
//! 丸めた端と真の端の間に覆いの端が入ることがない。誤差なしの二和で真の端を厳密に取り、チャンクの座標と局所の端の
//! 組を2億3千万件ぶん調べても、間に入りうる組は1件も出なかった。それでも幅を足す理由は覆いの側と同じで、この安全が
//! 丸めの回数に依存した性質だからである。
//!
//! 外へ広げすぎる側の害は、完全と言えたはずの縁の問い合わせを不完全と言うことだけである。その問い合わせは当たりを
//! 捨てて「何にも当たらない」の側で答えるため、確定でない当たりを確定と言うことは起きない。2つの誤りは重さが違う
//! ため、幅は誤差の上界の上からさらに安全側へ丸めて決める。
//!
//! 以下では倍精度の演算1回の相対誤差の上限である2の53乗分の1をuと書き、標準模型 fl(x∘y) = (x∘y)(1+δ)、δの絶対値は
//! u以下、を使う。係数は2次以上の項を吸収した整数にする。
//!
//! 半径ぶん広げる側の演算列は、広げる前の端をe・広げる長さをwとして、p = fl(e ± w) の1回だけである。wは単精度から
//! の変換であり丸めを通らない。|p − (e ± w)| は u·|e ± w| 以下、すなわち u·(|e| + w) 以下である。eは箱の2つの端の
//! どちらにもなるため、幅は2つの端の絶対値の和で押さえる。
//!
//! 掃く側の演算列は、掃く前の箱の端をe・変位の成分をD・比をtとして、m = fl(D·t)、q = fl(e + m) である。Dは単精度
//! からの変換であり丸めを通らない。真の端は Q = e + D·t であり、q − Q = e·δ2 + D·t·[(1+δ1)(1+δ2) − 1] になる。
//! 角括弧の中の絶対値は3u以下、|D·t| は計算した移動の絶対値の(1+2u)倍以下であるから、|q − Q| は
//! 4u·(|e| + |移動|) 以下である。切り詰めでない掃引は比が1であり、積が丸めを通らないぶんこれより小さい。
//!
//! 線分の側の演算列は、端をa・もう一方の端をb・比をtとして、d = fl(b − a)、m = fl(d·t)、p = fl(a + m) である。
//! 真の点は P = a + (b − a)·t であり、3つの丸めをδ1・δ2・δ3と置くと
//! p − P = a·δ3 + (b − a)·t·[(1+δ1)(1+δ2)(1+δ3) − 1] になる。角括弧の中の絶対値は4u以下、|(b − a)·t| は
//! |a| + |b| 以下であるから、|p − P| は u·|a| + 4u·(|a| + |b|)以下、すなわち 5u·(|a| + |b|) 以下である。
//!
//! 写す側の演算列は、群の大域原点をo・局所の箱の端をlとして、p = fl(o + l) の1回だけである。lは単精度からの変換で
//! あり丸めを通らない。|p − (o + l)| は u·|o + l| 以下、すなわち u·(|o| + |l|) 以下である。lは箱の2つの端の
//! どちらにもなるため、幅は原点と2つの端の絶対値の和で押さえる。
//!
//! したがって幅は、演算に入る値の絶対値の和に2の49乗分の1(16u)を掛けた値にする。16uを選ぶのは、上の上界(半径ぶん
//! 広げる側と写す側は1u、掃く側は4u、線分の側は5u)を3倍以上上回り、そのうえで絶対値の和を求める加算の丸め(uの1倍あまり)と
//! 端へ幅を足し引きする加算の丸め(uの1倍あまり)を足しても、なお上界を上回るためである。2の冪を掛ける積は丸めを
//! 通らないため、相対量そのものは誤差を持ち込まない。
//!
//! 定義域。端の絶対値は、形状の座標の上限である2の24乗メートルに、チャンクの基準原点の大きさを足した範囲に収まる。
//! 基準原点はチャンクの座標(32ビット整数)とチャンクの一辺の積であるから、和は2の40乗メートルの桁を出ない。この
//! 範囲では絶対値の和も幅も倍精度の正規化数に収まり、桁あふれも非正規化数への落ち込みも起きない。範囲を大きく出た
//! 値が来て和が桁あふれした場合、幅は無限大になって端も有限でなくなるが、その端はチャンクの座標へ写す入口が
//! 型付きエラーで拒む。黙って内側へ縮む側には落ちない。
//! 参照: `crates/blitz_collision/src/shape/global_axis_aligned_box.rs`

// 演算に入る値の絶対値の和に掛ける相対量。2の49乗分の1である。
const 箱の端の丸めを包む幅の相対量: f64 = 1.0 / 562_949_953_421_312.0;

// 全方向へ同じ長さだけ広げた端が受ける丸めを外から包む幅。広げる前の箱の両端と広げる長さから軸ごとに決まる。
pub(super) fn 全方向へ広げた端が受ける丸めを包む幅を求める(
    広げる前の最小の端: [f64; 3],
    広げる前の最大の端: [f64; 3],
    長さ: f64,
) -> [f64; 3] {
    [0usize, 1, 2].map(|軸| (広げる前の最小の端[軸].abs() + 広げる前の最大の端[軸].abs() + 長さ) * 箱の端の丸めを包む幅の相対量)
}

// 移動のぶんだけ掃いた端が受ける丸めを外から包む幅。掃く前の箱の両端と、比を掛けた移動から軸ごとに決まる。
pub(super) fn 掃いた端が受ける丸めを包む幅を求める(
    掃く前の最小の端: [f64; 3],
    掃く前の最大の端: [f64; 3],
    移動: [f64; 3],
) -> [f64; 3] {
    [0usize, 1, 2].map(|軸| (掃く前の最小の端[軸].abs() + 掃く前の最大の端[軸].abs() + 移動[軸].abs()) * 箱の端の丸めを包む幅の相対量)
}

// 線分を比のぶんだけ進めた端が受ける丸めを外から包む幅。線分の両端の成分から軸ごとに決まる。
pub(super) fn 線分を比のぶんだけ進めた端が受ける丸めを包む幅を求める(
    端: [f64; 3], もう一方の端: [f64; 3]
) -> [f64; 3] {
    [0usize, 1, 2].map(|軸| (端[軸].abs() + もう一方の端[軸].abs()) * 箱の端の丸めを包む幅の相対量)
}

// 局所の箱を大域原点から写した端が受ける丸めを外から包む幅。群の大域原点と局所の箱の両端から軸ごとに決まる。
pub(super) fn 大域原点から写した端が受ける丸めを包む幅を求める(
    大域原点: [f64; 3],
    局所の最小の端: [f64; 3],
    局所の最大の端: [f64; 3],
) -> [f64; 3] {
    [0usize, 1, 2].map(|軸| (大域原点[軸].abs() + 局所の最小の端[軸].abs() + 局所の最大の端[軸].abs()) * 箱の端の丸めを包む幅の相対量)
}
