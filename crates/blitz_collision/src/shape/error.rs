//! 直方体の値が満たすべき条件を破ったときの失敗。
//!
//! 破れた成分を値でなく軸の名前で示すのは、この型が`Copy`と`Eq`を導出でき、世界側のエラーへそのまま合流できる
//! 形に保つためである。世界の範囲(チャンクの基準原点からの許容等)の破れはここに無い。衝突数学層は世界を知らず、
//! その検査は形を世界の物体へ束ねる側が持つ。

use super::coordinate_limit::形状の座標の絶対値の上限メートル;

/// 直方体の生成が拒否する理由。
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum 直方体の生成エラー {
    /// 任意姿勢の直方体の中心に有限でない成分が含まれる。
    #[error("直方体の中心の{軸}成分に有限でない値が含まれる")]
    中心が有限でない {
        /// 破れた成分の軸の名前。
        軸: &'static str,
    },
    /// 任意姿勢の直方体の中心の成分の絶対値が、形状の座標の上限を越えた。
    #[error("直方体の中心の{軸}成分の絶対値が形状の座標の上限{}メートルを越えた", 形状の座標の絶対値の上限メートル)]
    中心が上限を越えている {
        /// 破れた成分の軸の名前。
        軸: &'static str,
    },
    /// 直方体の軸ごとの半分の長さに負か有限でない成分が含まれる。
    #[error("直方体の軸ごとの半分の長さの{軸}成分が負であるか有限でない")]
    半分の長さが負か非有限 {
        /// 破れた成分の軸の名前。
        軸: &'static str,
    },
    /// 直方体の軸ごとの半分の長さの成分が、形状の座標の上限を越えた。
    #[error(
        "直方体の軸ごとの半分の長さの{軸}成分が形状の座標の上限{}メートルを越えた",
        形状の座標の絶対値の上限メートル
    )]
    半分の長さが上限を越えている {
        /// 破れた成分の軸の名前。
        軸: &'static str,
    },
    /// 直方体の軸ごとの半分の長さのうち2軸以上が0であり、直方体が線分か点へ退化している。この退化は接触点集合が同じ位置の接触点を重ねて作るだけでなく、詳細判定と掃引の全経路へ同型の穴を持ち込むため、形の入口で閉じる。
    #[error("直方体の軸ごとの半分の長さのうち2軸以上が0であり、直方体が線分か点へ退化している")]
    半分の長さが2軸以上で零,
    /// 軸平行の直方体の端に有限でない成分が含まれる。
    #[error("軸平行の直方体の端の{軸}成分に有限でない値が含まれる")]
    箱の端が有限でない {
        /// 破れた成分の軸の名前。
        軸: &'static str,
    },
    /// 軸平行の直方体の最小の端が最大の端を越えた。
    #[error("軸平行の直方体の{軸}成分で最小の端が最大の端を越えている")]
    箱の最小が最大を越えている {
        /// 破れた成分の軸の名前。
        軸: &'static str,
    },
}

