//! 直方体のカプセルの掃引の問い合わせ: カプセルを変位の分だけ動かそうとしたとき、直方体に触れるまでに
//! どこまで動けるかを求める操作サービス。直方体の線分の問い合わせをコンストラクタで組んで保持するため、
//! 問い合わせの署名に形が現れない。
//!
//! 線分の問い合わせを保持するのは、掃引の始まりでカプセルの軸そのものが直方体を貫いているかという問いが、
//! 軸の線分が直方体に当たるかという問いと同じものだからである。貫いていれば軸から直方体までの隔たりは0であり、
//! 特徴ごとの最近接をいくら数えてもその0には達しない。軸の両端も辺も頂点も直方体の面から離れているためである。
//!
//! 1回の問い合わせでヒープを確保しない。持つのは特徴ごとの最小の候補1つだけである。
//!
//! 接触の単位法線を単精度へ狭めるのはここ1箇所である。72通りの候補それぞれで平方根と割り算を通すのを避けるため、
//! 求解は接触位置から軸へ向かう倍精度の変位のまま持ち回り、最小の候補が決まってから正して狭める。

use crate::shape::任意姿勢の直方体;
use crate::solver::掃引で動けた割合;

use super::capsule::直方体を掃引するカプセル;
use super::error::直方体の問い合わせエラー;
use super::segment_hit::線分が直方体に最初に当たる点;
use super::segment_query::直方体の線分の問い合わせ;
use super::segment_through_box::直方体を貫く線分;
use super::sweep_contact::{カプセルが直方体に最初に触れる点, 掃引したカプセルの直方体への接触};
use super::sweep_place::直方体で触れた場所;
use super::sweep_solver::カプセルと直方体の接触の求解;

/// 任意姿勢の直方体のカプセルの掃引の問い合わせ。直方体の線分の問い合わせを保持し、掃引の接触を答える操作サービスである。
pub struct 直方体のカプセルの掃引の問い合わせ {
    線分の問い合わせ: 直方体の線分の問い合わせ,
}

impl 直方体のカプセルの掃引の問い合わせ {
    /// 直方体を倍精度で読み直した線分の問い合わせを組んで保持する。読み直しはこの生成の1回だけ行う。
    pub fn 直方体から生成する(直方体: &任意姿勢の直方体) -> Self {
        Self {
            線分の問い合わせ: 直方体の線分の問い合わせ::直方体から生成する(直方体),
        }
    }

    /// カプセルが直方体に最初に触れる点を求める。掃引の始まりで既に半径以内に居るカプセルは、動けた割合0で返す。
    pub fn カプセルが直方体に最初に触れる点を求める(
        &self,
        カプセル: &直方体を掃引するカプセル,
    ) -> Result<カプセルが直方体に最初に触れる点, 直方体の問い合わせエラー> {
        let 求解 = カプセルと直方体の接触の求解::生成する(カプセル, self.線分の問い合わせ.幾何());
        if let Some(場所) = self.掃引の始まりで触れている場所を求める(カプセル, &求解)? {
            let 接触 = self.接触を組む(掃引で動けた割合::一歩も動けなかった(), 場所)?;
            return Ok(カプセルが直方体に最初に触れる点::直方体に触れる(接触));
        }
        match 求解.掃引の途中で最初に触れる接触を求める()? {
            Some(触れ始める) => Ok(カプセルが直方体に最初に触れる点::直方体に触れる(
                self.接触を組む(触れ始める.動けた割合(), 触れ始める.場所())?,
            )),
            None => Ok(カプセルが直方体に最初に触れる点::直方体に触れない),
        }
    }

    // 掃引の始まりで既に触れているなら、その場所。軸が直方体を貫く場合を先に見て、次に特徴ごとの最近接を半径と比べる。
    fn 掃引の始まりで触れている場所を求める(
        &self,
        カプセル: &直方体を掃引するカプセル,
        求解: &カプセルと直方体の接触の求解<'_>,
    ) -> Result<Option<直方体で触れた場所>, 直方体の問い合わせエラー> {
        if let Some(貫いた場所) = self.軸が直方体を貫く場所を求める(カプセル)? {
            return Ok(Some(貫いた場所));
        }
        let Some(最近接) = 求解.掃引の始まりで最も近い特徴を求める()? else {
            return Ok(None);
        };
        if 最近接.隔たりの二乗() <= 求解.半径の二乗() {
            return Ok(Some(最近接.場所()));
        }
        Ok(None)
    }

    // 掃引の始まりで軸そのものが直方体と交わる場所。接触位置から軸へ向かう変位を零で置くのは、軸が直方体の中に
    // 在るときに押し戻す向きがこの層では決まらないためである。答えを組む側が、当たった特徴の外向きの単位法線を使う。
    fn 軸が直方体を貫く場所を求める(
        &self,
        カプセル: &直方体を掃引するカプセル,
    ) -> Result<Option<直方体で触れた場所>, 直方体の問い合わせエラー> {
        let 軸の線分 = 直方体を貫く線分::生成する(カプセル.軸の始点(), カプセル.軸の終点());
        match self.線分の問い合わせ.線分が直方体に最初に当たる点を求める(&軸の線分)? {
            線分が直方体に最初に当たる点::直方体に当たらない => Ok(None),
            線分が直方体に最初に当たる点::直方体に当たる(当たり) => Ok(Some(直方体で触れた場所::生成する(
                当たり.交差位置(),
                crate::shape::形の局所座標の変位::零(),
                当たり.当たった特徴(),
            ))),
        }
    }

    // 触れた場所から答えを組む。接触位置から軸へ向かう変位を長さ1に正した向きが接触の単位法線であり、
    // 長さが0で向きが定まらないときは触れた特徴の外向きの単位法線を使う。
    fn 接触を組む(
        &self,
        動けた割合: 掃引で動けた割合,
        場所: 直方体で触れた場所,
    ) -> Result<掃引したカプセルの直方体への接触, 直方体の問い合わせエラー> {
        let 単位法線 = match 場所.接触位置から軸への変位().長さで正した方向へ狭める() {
            Some(結果) => 結果?,
            None => self.線分の問い合わせ.幾何().特徴の外向きの単位法線を求める(場所.触れた特徴())?,
        };
        Ok(掃引したカプセルの直方体への接触::生成する(
            動けた割合,
            場所.接触位置(),
            単位法線,
            場所.触れた特徴(),
        ))
    }
}
