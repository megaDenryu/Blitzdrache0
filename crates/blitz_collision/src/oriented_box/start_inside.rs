//! 直方体の中に在る点に最も近い面を求める工程。受け取るのは局所座標の点、返すのは6つの面のうち1つである。
//!
//! これが要るのは、線分の始点が既に直方体の中に在るときの答えを組むためである。そのとき交差の時刻は0であり、
//! 交差の位置は始点そのものであるが、法線をどの面から取るかは幾何だけでは決まらない。押し戻す距離が最も短い
//! 面、すなわち面までの深さが最も浅い面を選ぶ。線分の問い合わせが「始点が地表の下なら交差時刻0」とした
//! 高さ場の設計と同じ考えである。
//! 参照: `crates/blitz_collision/src/height_field/cell_segment_intersection.rs`
//!
//! 深さが並んだときは軸の並びの先に来る面を残す。軸の並びも面の向きの並びも固定であるから、これで答えが
//! 入力だけで決まる。

use crate::shape::{
    任意姿勢の直方体の倍精度の幾何, 形の局所座標の位置, 直方体の面の向き, 直方体自身の座標軸
};

use super::feature::直方体の面;

impl 任意姿勢の直方体の倍精度の幾何 {
    pub(super) fn 点に最も近い面を求める(&self, 点: 形の局所座標の位置) -> 直方体の面 {
        let mut 最も近い面 = self.軸1本の近い側の面を求める(点, 直方体自身の座標軸::X軸);
        let mut 最も浅い深さ = self.面までの深さを求める(点, 最も近い面);
        for 軸 in [直方体自身の座標軸::Y軸, 直方体自身の座標軸::Z軸] {
            let 面 = self.軸1本の近い側の面を求める(点, 軸);
            let 深さ = self.面までの深さを求める(点, 面);
            if 深さ < 最も浅い深さ {
                最も浅い深さ = 深さ;
                最も近い面 = 面;
            }
        }
        最も近い面
    }

    // その軸に垂直な2つの面のうち、点が寄っている側の面。中心のちょうど上に在る点は正の側として扱う。
    fn 軸1本の近い側の面を求める(&self, 点: 形の局所座標の位置, 軸: 直方体自身の座標軸) -> 直方体の面 {
        let 隔たり = self.中心から見た軸に沿った隔たりを求める(点, 軸);
        直方体の面::生成する(軸, 直方体の面の向き::実数の符号が指す側を求める(隔たり))
    }

    // 点からその面までの、面の法線に沿った隔たり。点が直方体の中に在るなら0以上である。
    fn 面までの深さを求める(&self, 点: 形の局所座標の位置, 面: 直方体の面) -> f64 {
        self.軸に沿った半分の長さのメートル(面.軸()) - self.中心から見た軸に沿った隔たりを求める(点, 面.軸()).abs()
    }
}
