//! 直方体の頂点と、軸の端および軸の内側の接触。
//!
//! 軸の端との接触は、半径の球が固定の点へ達する条件であるから、中心と点の隔たりの二乗が半径の二乗に等しい
//! という2次方程式になる。制約は無い。球はカプセルの一部であるから、この根はどれも実際に触れている時刻である。
//!
//! 軸の内側との接触は、頂点から軸の直線までの隔たりが半径に等しい条件である。隔たりの二乗は
//! 「頂点から軸の始点への変位と軸の変位の外積」の長さの二乗を軸の長さの二乗で割ったものであるから、
//! 分母を払うと2次方程式になる。直線は軸より長いため、根の時刻で最近接点が軸の内側に収まることを確かめる。

use crate::shape::形の局所座標の変位;
use crate::solver::掃引の2次方程式;
use crate::solver::軸の端;

use super::error::直方体の問い合わせエラー;
use super::feature::{直方体で当たった特徴, 直方体の頂点};
use super::sweep_place::{直方体で触れた場所, 軸と特徴の最近接};
use super::sweep_solver::カプセルと直方体の接触の求解;

impl カプセルと直方体の接触の求解<'_> {
    pub(super) fn 頂点と軸の端の方程式を組む(&self, 端: 軸の端, 頂点: 直方体の頂点) -> 掃引の2次方程式 {
        掃引の2次方程式::点と球の隔たりから組む(
            self.基準の点から時刻の軸の端への変位(self.幾何().頂点の位置を求める(頂点), 端, 0.0),
            self.掃引の変位(),
            self.半径の二乗(),
        )
    }

    pub(super) fn 頂点と軸の端の最近接を求める(
        &self,
        端: 軸の端,
        頂点: 直方体の頂点,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, 直方体の問い合わせエラー> {
        let 頂点から軸へ = self.基準の点から時刻の軸の端への変位(self.幾何().頂点の位置を求める(頂点), 端, 時刻);
        Ok(Some(self.頂点に触れた最近接を組む(頂点, 頂点から軸へ)))
    }

    // 軸の内側と頂点の方程式。軸の長さが0のカプセル(球)には内側が無いため値なしを返す。
    pub(super) fn 頂点と軸の内側の方程式を組む(&self, 頂点: 直方体の頂点) -> Option<掃引の2次方程式> {
        let 軸 = self.軸の変位();
        let 軸の長さの二乗 = 軸.長さの二乗();
        if 軸の長さの二乗 <= 0.0 {
            return None;
        }
        Some(掃引の2次方程式::直線と球の隔たりから組む(
            self.基準の点から時刻の軸の端への変位(self.幾何().頂点の位置を求める(頂点), 軸の端::始点の側, 0.0),
            self.掃引の変位(),
            軸,
            軸の長さの二乗,
            self.半径の二乗(),
        ))
    }

    // 時刻での、頂点と軸の直線の最近接。最近接点が軸の外にあるなら、その接触は軸の端の候補が答えるため値なしを返す。
    pub(super) fn 頂点と軸の内側の最近接を求める(
        &self,
        頂点: 直方体の頂点,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, 直方体の問い合わせエラー> {
        let 軸 = self.軸の変位();
        let 軸の長さの二乗 = 軸.長さの二乗();
        if 軸の長さの二乗 <= 0.0 {
            return Ok(None);
        }
        let 頂点から始点へ = self.基準の点から時刻の軸の端への変位(self.幾何().頂点の位置を求める(頂点), 軸の端::始点の側, 時刻);
        let 軸の比 = -頂点から始点へ.内積(軸) / 軸の長さの二乗;
        if !(0.0..=1.0).contains(&軸の比) {
            return Ok(None);
        }
        Ok(Some(self.頂点に触れた最近接を組む(
            頂点,
            頂点から始点へ.加える(軸.実数倍する(軸の比)),
        )))
    }

    fn 頂点に触れた最近接を組む(
        &self, 頂点: 直方体の頂点, 頂点から軸へ: 形の局所座標の変位
    ) -> 軸と特徴の最近接 {
        軸と特徴の最近接::生成する(
            頂点から軸へ.長さの二乗(),
            直方体で触れた場所::生成する(
                self.幾何().頂点の位置を求める(頂点),
                頂点から軸へ,
                直方体で当たった特徴::直方体の頂点(頂点),
            ),
        )
    }
}
