//! 直方体のどの部分に当たったか。面6つ・辺12本・頂点8つを、軸と軸ごとの側で指す。
//!
//! 番号で指さないのは、答えを受け取った側が「3番の辺」がどこかを別の決まりで覚えることになるためである。
//! 軸と側で指せば、名前だけでどこに当たったかが決まる。
//!
//! 辺が持つ2つの側は、沿う軸の次の軸と、そのさらに次の軸に対応する。巡回の順は`直方体自身の座標軸`が定める。
//! 頂点が持つ3つの側は、軸の並びの順にx軸・y軸・z軸へ対応する。

use crate::shape::{直方体の面の向き, 直方体自身の座標軸};

/// 直方体の6つの面のうち1つ。1本の軸と、その軸のどちら側かで決まる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 直方体の面 {
    軸: 直方体自身の座標軸,
    側: 直方体の面の向き,
}

impl 直方体の面 {
    /// 軸とその軸のどちら側かから作る。どの組み合わせも実在する面であるため検査は無い。
    pub fn 生成する(軸: 直方体自身の座標軸, 側: 直方体の面の向き) -> Self {
        Self { 軸, 側 }
    }

    /// この面が垂直に交わる、直方体自身の軸。
    pub fn 軸(&self) -> 直方体自身の座標軸 {
        self.軸
    }

    /// この面が軸のどちら側に在るか。
    pub fn 側(&self) -> 直方体の面の向き {
        self.側
    }
}

/// 直方体の12本の辺のうち1本。1本の軸に沿って伸び、残る2本の軸それぞれについてどちら側に在るかで決まる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 直方体の辺 {
    沿う軸: 直方体自身の座標軸,
    次の軸の側: 直方体の面の向き,
    次の次の軸の側: 直方体の面の向き,
}

impl 直方体の辺 {
    /// 沿う軸と、残る2本の軸それぞれの側から作る。どの組み合わせも実在する辺であるため検査は無い。
    pub fn 生成する(
        沿う軸: 直方体自身の座標軸, 次の軸の側: 直方体の面の向き, 次の次の軸の側: 直方体の面の向き
    ) -> Self {
        Self {
            沿う軸,
            次の軸の側,
            次の次の軸の側,
        }
    }

    /// この辺が伸びる、直方体自身の軸。
    pub fn 沿う軸(&self) -> 直方体自身の座標軸 {
        self.沿う軸
    }

    /// この辺の始点になる頂点。沿う軸について負の側を取り、残る2本の軸は辺が持つ側をそのまま使う。
    /// 辺の始点と終点をこの向きで決めるのは、辺の上の比を0から1へ測る向きを1箇所で固定するためである。
    pub fn 始点の頂点を求める(&self) -> 直方体の頂点 {
        直方体の頂点::軸の並びの順の側から生成する(
            直方体自身の座標軸::並べる().map(|軸| self.軸ごとの側(軸).unwrap_or(直方体の面の向き::軸の負の側)),
        )
    }

    /// 指定した軸についてこの辺がどちら側に在るか。沿う軸を渡すと値なしを返す。
    pub fn 軸ごとの側(&self, 軸: 直方体自身の座標軸) -> Option<直方体の面の向き> {
        if 軸 == self.沿う軸.次の軸() {
            return Some(self.次の軸の側);
        }
        if 軸 == self.沿う軸.次の軸().次の軸() {
            return Some(self.次の次の軸の側);
        }
        None
    }
}

/// 直方体の8つの頂点のうち1つ。3本の軸それぞれについてどちら側に在るかで決まる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 直方体の頂点 {
    軸ごとの側: [直方体の面の向き; 3],
}

impl 直方体の頂点 {
    /// 軸の並びの順に3つの側を並べた組から作る。どの組み合わせも実在する頂点であるため検査は無い。
    pub fn 軸の並びの順の側から生成する(軸ごとの側: [直方体の面の向き; 3]) -> Self {
        Self { 軸ごとの側 }
    }

    /// 指定した軸についてこの頂点がどちら側に在るか。
    pub fn 軸ごとの側(&self, 軸: 直方体自身の座標軸) -> 直方体の面の向き {
        self.軸ごとの側[軸.並びの位置()]
    }
}

/// カプセルまたは線分が直方体のどの部分に当たったか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 直方体で当たった特徴 {
    /// 面の内側に当たった。法線はその面の外向きの単位法線である。
    直方体の面(直方体の面),
    /// 辺の上に当たった。法線は辺を挟む2つの面の外向きの単位法線を足して正した向きである。
    直方体の辺(直方体の辺),
    /// 頂点に当たった。法線は頂点に集まる3つの面の外向きの単位法線を足して正した向きである。
    直方体の頂点(直方体の頂点),
}
