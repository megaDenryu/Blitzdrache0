//! 軸平行に据えた直方体への線分の反証。回転が恒等であるため、期待値は割り切れる十進の値で書ける。
//!
//! 見るのは6つである。面の内側に当たること、角へ向かう線分が頂点として返ること、直方体を貫いた線分が
//! 手前の面で答えること、届かない線分が当たらないこと、角の脇をかすめる線分が当たらないこと、
//! 始点が中に在る線分が時刻0と最も近い面で返ることである。

use blitz_math::クォータニオン;

use crate::shape::{直方体の面の向き, 直方体自身の座標軸};

use super::feature::{直方体で当たった特徴, 直方体の面, 直方体の頂点};
use super::query_fixture::{三成分が近いことを確かめる, 位置の成分, 方向の成分, 直方体を作る, 線分を作る};
use super::segment_hit::{直方体への最初の当たり, 線分が直方体に最初に当たる点};
use super::segment_query::直方体の線分の問い合わせ;

fn 原点に据えた箱の当たりを求める(半分: [f32; 3], 始点: [f64; 3], 終点: [f64; 3]) -> 線分が直方体に最初に当たる点 {
    let 直方体 = 直方体を作る([0.0, 0.0, 0.0], クォータニオン::恒等(), 半分);
    let 線分 = 線分を作る(始点, 終点);
    match 直方体の線分の問い合わせ::直方体から生成する(&直方体).線分が直方体に最初に当たる点を求める(&線分)
    {
        Ok(答え) => 答え,
        Err(誤り) => panic!("線分の問い合わせが失敗した: {誤り}"),
    }
}

fn 当たりを取り出す(答え: 線分が直方体に最初に当たる点) -> 直方体への最初の当たり {
    match 答え {
        線分が直方体に最初に当たる点::直方体に当たる(当たり) => 当たり,
        線分が直方体に最初に当たる点::直方体に当たらない => panic!("当たるはずの線分が当たらなかった"),
    }
}

#[test]
fn 面の内側へ向かう線分は面として当たる() {
    let 当たり = 当たりを取り出す(原点に据えた箱の当たりを求める(
        [1.0, 2.0, 3.0],
        [-5.0, 0.0, 0.0],
        [5.0, 0.0, 0.0],
    ));
    assert_eq!(当たり.交差時刻().値(), 0.4);
    assert_eq!(位置の成分(当たり.交差位置()), [-1.0, 0.0, 0.0]);
    assert_eq!(方向の成分(当たり.接触面の単位法線()), [-1.0, 0.0, 0.0]);
    assert_eq!(
        当たり.当たった特徴(),
        直方体で当たった特徴::直方体の面(直方体の面::生成する(直方体自身の座標軸::X軸, 直方体の面の向き::軸の負の側))
    );
}

#[test]
fn 角へ向かう線分は頂点として当たる() {
    let 当たり = 当たりを取り出す(原点に据えた箱の当たりを求める(
        [1.0, 1.0, 1.0],
        [-4.0, -4.0, -4.0],
        [4.0, 4.0, 4.0],
    ));
    assert_eq!(当たり.交差時刻().値(), 0.375);
    assert_eq!(位置の成分(当たり.交差位置()), [-1.0, -1.0, -1.0]);
    let 三分の一の平方根 = (1.0_f64 / 3.0).sqrt();
    三成分が近いことを確かめる(
        方向の成分(当たり.接触面の単位法線()).map(f64::from),
        [-三分の一の平方根; 3],
        1.0e-6,
        "頂点に当たった法線",
    );
    assert_eq!(
        当たり.当たった特徴(),
        直方体で当たった特徴::直方体の頂点(直方体の頂点::軸の並びの順の側から生成する(
            [直方体の面の向き::軸の負の側; 3]
        ))
    );
}

#[test]
fn 直方体を貫いた線分でも手前の面で答える() {
    let 当たり = 当たりを取り出す(原点に据えた箱の当たりを求める(
        [1.0, 1.0, 1.0],
        [-2.0, 0.0, 0.0],
        [2.0, 0.0, 0.0],
    ));
    assert_eq!(当たり.交差時刻().値(), 0.25);
    assert_eq!(位置の成分(当たり.交差位置()), [-1.0, 0.0, 0.0]);
    assert_eq!(方向の成分(当たり.接触面の単位法線()), [-1.0, 0.0, 0.0]);
}

#[test]
fn 直方体へ届かない線分は当たらない() {
    let 答え = 原点に据えた箱の当たりを求める([1.0, 1.0, 1.0], [-5.0, 0.0, 0.0], [-3.0, 0.0, 0.0]);
    assert_eq!(答え, 線分が直方体に最初に当たる点::直方体に当たらない);
}

#[test]
fn 角の脇をかすめる線分は当たらない() {
    let 答え = 原点に据えた箱の当たりを求める([1.0, 1.0, 1.0], [-5.0, 0.0, 0.0], [0.0, 5.0, 0.0]);
    assert_eq!(答え, 線分が直方体に最初に当たる点::直方体に当たらない);
}

#[test]
fn 始点が中に在る線分は時刻0と最も近い面で返る() {
    let 当たり = 当たりを取り出す(原点に据えた箱の当たりを求める(
        [1.0, 2.0, 3.0],
        [0.5, 0.0, 0.0],
        [10.0, 0.0, 0.0],
    ));
    assert_eq!(当たり.交差時刻().値(), 0.0);
    assert_eq!(位置の成分(当たり.交差位置()), [0.5, 0.0, 0.0]);
    assert_eq!(方向の成分(当たり.接触面の単位法線()), [1.0, 0.0, 0.0]);
    assert_eq!(
        当たり.当たった特徴(),
        直方体で当たった特徴::直方体の面(直方体の面::生成する(直方体自身の座標軸::X軸, 直方体の面の向き::軸の正の側))
    );
}
