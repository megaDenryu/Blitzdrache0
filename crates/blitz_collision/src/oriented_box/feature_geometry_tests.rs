//! 直方体の特徴の位置と向きの反証。軸平行に据えた直方体で、頂点・辺・面の期待値を割り切れる十進の値で書く。
//!
//! 中心を原点から離すのは、中心を足し忘れる誤りが原点では見えないためである。半分の長さを軸ごとに変えるのは、
//! 軸の取り違えが同じ長さでは見えないためである。

use blitz_math::クォータニオン;

use crate::shape::{
    任意姿勢の直方体の倍精度の幾何, 形の局所座標の変位, 直方体の面の向き, 直方体自身の座標軸
};

use super::feature::{直方体で当たった特徴, 直方体の辺, 直方体の面, 直方体の頂点};
use super::query_fixture::{位置の成分, 直方体を作る};

fn 中心をずらした箱の幾何() -> 任意姿勢の直方体の倍精度の幾何 {
    任意姿勢の直方体の倍精度の幾何::直方体から組む(&直方体を作る([10.0, 20.0, 30.0], クォータニオン::恒等(), [1.0, 2.0, 3.0]))
}

fn 向きの成分(向き: 形の局所座標の変位) -> [f64; 3] {
    [向き.xのメートル(), 向き.yのメートル(), 向き.zのメートル()]
}

fn 手前上の辺() -> 直方体の辺 {
    直方体の辺::生成する(直方体自身の座標軸::X軸, 直方体の面の向き::軸の正の側, 直方体の面の向き::軸の負の側)
}

#[test]
fn 頂点の位置は中心へ軸ごとの半分の長さを符号付きで足した点になる() {
    let 頂点 = 直方体の頂点::軸の並びの順の側から生成する(
        [直方体の面の向き::軸の正の側, 直方体の面の向き::軸の負の側, 直方体の面の向き::軸の正の側],
    );
    assert_eq!(位置の成分(中心をずらした箱の幾何().頂点の位置を求める(頂点)), [11.0, 18.0, 33.0]);
}

#[test]
fn 辺の始点は沿う軸の負の側の頂点であり変位は軸の長さになる() {
    let 幾何 = 中心をずらした箱の幾何();
    assert_eq!(位置の成分(幾何.辺の始点の位置を求める(手前上の辺())), [9.0, 22.0, 27.0]);
    assert_eq!(向きの成分(幾何.辺の変位を求める(手前上の辺())), [2.0, 0.0, 0.0]);
}

#[test]
fn 面の中央は中心から外向きへ半分の長さだけ進んだ点になる() {
    let 幾何 = 中心をずらした箱の幾何();
    let 面 = 直方体の面::生成する(直方体自身の座標軸::Z軸, 直方体の面の向き::軸の正の側);
    assert_eq!(位置の成分(幾何.面の中央の位置を求める(面)), [10.0, 20.0, 33.0]);
    assert_eq!(向きの成分(幾何.面の外向きの単位向きを求める(面)), [0.0, 0.0, 1.0]);
}

#[test]
fn 辺の外向きの向きは挟む二つの面の法線の和になる() {
    assert_eq!(
        向きの成分(中心をずらした箱の幾何().特徴の外向きの向きを求める(直方体で当たった特徴::直方体の辺(手前上の辺()))),
        [0.0, 1.0, -1.0]
    );
}

#[test]
fn 面の四角形の外に落ちた足は内側と判定しない() {
    let 幾何 = 中心をずらした箱の幾何();
    let 面 = 直方体の面::生成する(直方体自身の座標軸::Z軸, 直方体の面の向き::軸の正の側);
    assert!(幾何.面の上の点が内側にあるか(面, crate::shape::形の局所座標の位置::検査済みの成分から組む(10.5, 21.0, 33.0)));
    assert!(!幾何.面の上の点が内側にあるか(面, crate::shape::形の局所座標の位置::検査済みの成分から組む(11.5, 20.0, 33.0)));
}
