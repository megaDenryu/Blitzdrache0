//! 接触の特徴の候補: カプセルのどの部分が直方体のどの特徴に触れるかの組み合わせである。
//! 掃引の求解は、5種類を数え上げた72通りの候補を1つずつ数え、それぞれの接触の時刻を解いて最小を選ぶ。
//!
//! 5種類で足りる根拠は、最初に触れた瞬間の最近接点の対にある。カプセル側の最近接点は軸の2つの端か軸の内側の
//! どれかであり、直方体側の最近接点は面の内側か辺の内側か頂点のどれかである。種類の組み合わせは6つだが、
//! 軸の内側が面の内側に触れる場合は軸が面と平行であり、そのとき軸の端も同じ時刻に同じ隔たりへ達するか、
//! 軸を面へ落とした影が面の四角形の辺をまたぐため辺の候補が同じ時刻を答える。したがって軸の内側と面の組を
//! 数えない。高さ場の三角形で同じ数え方をした根拠と同じであり、面が三角形か四角形かはこの論証に効かない。
//!
//! 72通りの内訳は、面6つと軸の端2つで12、辺12本と軸の端2つで24、頂点8つと軸の端2つで16、辺12本と軸の内側で12、
//! 頂点8つと軸の内側で8である。
//!
//! どの候補も、平面・直線という直方体やカプセルより広がった形での接触を解くため、根の時刻で媒介変数が
//! 面・辺・軸の範囲に収まることを確かめる。収まる根はどれも実際に触れている時刻であるから、最初に触れる
//! 時刻より早くはなりえない。したがって候補ごとに範囲を満たす最小の根を取り、その最小を選べば答えになる。

use crate::solver::軸の端;

use super::feature::{直方体の辺, 直方体の面, 直方体の頂点};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 直方体との接触の特徴の候補 {
    面と軸の端 { 端: 軸の端, 面: 直方体の面 },
    辺と軸の端 { 端: 軸の端, 辺: 直方体の辺 },
    頂点と軸の端 { 端: 軸の端, 頂点: 直方体の頂点 },
    辺と軸の内側 { 辺: 直方体の辺 },
    頂点と軸の内側 { 頂点: 直方体の頂点 },
}

impl 直方体との接触の特徴の候補 {
    // 72通りの候補を、求解が数える順に並べる。並びを固定するのは、接触の時刻が並んだときにどの特徴の
    // 答えを返すかまで入力だけで決まるようにするためである。
    pub(super) fn 並べる() -> impl Iterator<Item = Self> {
        let 軸の端ごと = 軸の端::並べる().into_iter().flat_map(|端| {
            let 面ごと = 直方体の面::並べる().map(move |面| Self::面と軸の端 { 端, 面 });
            let 辺ごと = 直方体の辺::並べる().map(move |辺| Self::辺と軸の端 { 端, 辺 });
            let 頂点ごと = 直方体の頂点::並べる().map(move |頂点| Self::頂点と軸の端 { 端, 頂点 });
            面ごと.chain(辺ごと).chain(頂点ごと)
        });
        軸の端ごと
            .chain(直方体の辺::並べる().map(|辺| Self::辺と軸の内側 { 辺 }))
            .chain(直方体の頂点::並べる().map(|頂点| Self::頂点と軸の内側 { 頂点 }))
    }
}
