//! 当たった特徴の外向きの単位法線を、単精度の方向として組む工程。倍精度で導いた向きが単精度へ狭まる境界である。
//!
//! 特徴の位置と向きを読む工程(`feature_geometry.rs`)と別に置くのは、こちらが`blitz_math`の方向という外部の型へ
//! 渡す境界であり、狭める丸めと長さの検査がここにしか無いためである。
//!
//! 面の外向きの向きは既に長さ1であるが、辺と頂点の向きは2本または3本の単位軸の和であって長さが1でない。
//! どちらも同じ1つの経路で正すのは、面だけ正さない形にすると答えの組み方が2つに割れるためである。倍精度で
//! 長さ1に正した向きを単精度へ狭めるとき、長さは単精度の刻みぶんしか1から離れず、方向の生成の検査を通る。

use blitz_math::{ローカル, 方向};

use crate::shape::任意姿勢の直方体の倍精度の幾何;

use super::error::直方体の問い合わせエラー;
use super::feature::直方体で当たった特徴;

impl 任意姿勢の直方体の倍精度の幾何 {
    pub(super) fn 特徴の外向きの単位法線を求める(
        &self,
        特徴: 直方体で当たった特徴,
    ) -> Result<方向<ローカル>, 直方体の問い合わせエラー> {
        match self.特徴の外向きの向きを求める(特徴).長さで正した方向へ狭める() {
            Some(結果) => Ok(結果?),
            None => Err(直方体の問い合わせエラー::接触の単位法線が定まらない),
        }
    }
}
