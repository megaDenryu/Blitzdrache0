//! 3本の軸の区間を交差させて、線分が直方体の中に居る時刻の区間を求める工程。受け取るのは軸ごとの区間、
//! 返すのは最も遅く入る時刻・最も早く出る時刻・その入る時刻を決めた軸ごとの側である。
//!
//! 入る時刻を1つの数でなく軸ごとの側の組で覚えるのは、当たった特徴が面か辺か頂点かがここで決まるためである。
//! 2本の軸が同じ時刻に入るなら線分は辺へ、3本が同じ時刻に入るなら頂点へ達している。等号は丸めた値どうしの
//! 厳密な比較で見る。近い値を同じとみなす幅を置くと、幅の中の姿勢で答えが面と辺の間を揺れるためである。
//!
//! 入る時刻と出る時刻の初期値を無限大に置くのは、線分がその軸の向きへ動かない場合にその軸が何も課さないためである。
//! 3本とも何も課さなければ最も遅く入る時刻は負の無限大のままであり、線分は始まりから直方体の中に在る。

use super::slab::軸1本が線分へ課す区間;
use crate::shape::{直方体の面の向き, 直方体自身の座標軸};

pub(super) struct 線分が直方体の中に居る時刻の区間 {
    最も遅く入る時刻: f64,
    最も早く出る時刻: f64,
    入る時刻を決めた軸ごとの側: [Option<直方体の面の向き>; 3],
}

impl 線分が直方体の中に居る時刻の区間 {
    // 軸ごとの区間を交差させる。どの時刻も許さない軸が1つでもあれば、線分は直方体を通らない。
    pub(super) fn 軸ごとの区間を交差させて求める(軸ごとの区間: [軸1本が線分へ課す区間; 3]) -> Option<Self> {
        let mut 区間 = Self {
            最も遅く入る時刻: f64::NEG_INFINITY,
            最も早く出る時刻: f64::INFINITY,
            入る時刻を決めた軸ごとの側: [None; 3],
        };
        for 軸 in 直方体自身の座標軸::並べる() {
            match 軸ごとの区間[軸.並びの位置()] {
                軸1本が線分へ課す区間::どの時刻も許さない => return None,
                軸1本が線分へ課す区間::どの時刻も許す => {}
                軸1本が線分へ課す区間::入って出る {
                    入る時刻, 出る時刻, 入る側
                } => 区間.軸1本の区間を畳む(軸, 入る時刻, 出る時刻, 入る側),
            }
        }
        if 区間.最も遅く入る時刻 > 区間.最も早く出る時刻 {
            return None;
        }
        Some(区間)
    }

    // 1本の軸の区間を畳む。入る時刻がこれまでより遅ければ覚えている側をすべて捨て、同じなら側を足す。
    fn 軸1本の区間を畳む(
        &mut self, 軸: 直方体自身の座標軸, 入る時刻: f64, 出る時刻: f64, 入る側: 直方体の面の向き
    ) {
        self.最も早く出る時刻 = self.最も早く出る時刻.min(出る時刻);
        if 入る時刻 > self.最も遅く入る時刻 {
            self.最も遅く入る時刻 = 入る時刻;
            self.入る時刻を決めた軸ごとの側 = [None; 3];
        }
        if 入る時刻 == self.最も遅く入る時刻 {
            self.入る時刻を決めた軸ごとの側[軸.並びの位置()] = Some(入る側);
        }
    }

    pub(super) fn 最も遅く入る時刻(&self) -> f64 {
        self.最も遅く入る時刻
    }

    pub(super) fn 最も早く出る時刻(&self) -> f64 {
        self.最も早く出る時刻
    }

    pub(super) fn 入る時刻を決めた側(&self, 軸: 直方体自身の座標軸) -> Option<直方体の面の向き> {
        self.入る時刻を決めた軸ごとの側[軸.並びの位置()]
    }

    pub(super) fn 入る時刻を決めた軸の本数(&self) -> usize {
        self.入る時刻を決めた軸ごとの側.iter().flatten().count()
    }
}
