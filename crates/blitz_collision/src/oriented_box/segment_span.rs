//! 3本の軸の区間を交差させて、線分が直方体の中に居る時刻の区間を求める工程。受け取るのは軸ごとの区間、
//! 返すのは最も遅く入る時刻と最も早く出る時刻、および指定した時刻に境界へ載っている軸ごとの側である。
//!
//! 軸ごとの区間をそのまま保つのは、当たった特徴が面か辺か頂点かが「接触の時刻に直方体の境界へ載っている軸が
//! 何本あるか」で決まるためである。その軸は入る時刻を決めた軸だけではない。同じ時刻に出る側へ達する軸(稜へ
//! 一点で触れて離れる線分)と、その軸の向きへ動かず境界ちょうどを平行移動する軸も、同じ時刻に境界へ載っている。
//! 入る時刻を決めた軸だけを数えると、この2つの線分が面として返り、法線が実際には触れていない1つの面の向きになる。
//!
//! 等号は丸めた値どうしの厳密な比較で見る。近い値を同じとみなす幅を置くと、幅の中の姿勢で答えが面と辺の間を揺れる。
//!
//! 入る時刻と出る時刻の初期値を無限大に置くのは、線分がその軸の向きへ動かない場合にその軸が何も課さないためである。
//! 3本とも何も課さなければ最も遅く入る時刻は負の無限大のままであり、線分は始まりから直方体の中に在る。

use super::slab::軸1本が線分へ課す区間;
use crate::shape::{直方体の面の向き, 直方体自身の座標軸};

pub(super) struct 線分が直方体の中に居る時刻の区間 {
    軸ごとの区間: [軸1本が線分へ課す区間; 3],
    最も遅く入る時刻: f64,
    最も早く出る時刻: f64,
}

impl 線分が直方体の中に居る時刻の区間 {
    // 軸ごとの区間を交差させる。どの時刻も許さない軸が1つでもあれば、線分は直方体を通らない。
    pub(super) fn 軸ごとの区間を交差させて求める(軸ごとの区間: [軸1本が線分へ課す区間; 3]) -> Option<Self> {
        let mut 最も遅く入る時刻 = f64::NEG_INFINITY;
        let mut 最も早く出る時刻 = f64::INFINITY;
        for 区間 in &軸ごとの区間 {
            match 区間 {
                軸1本が線分へ課す区間::どの時刻も許さない => return None,
                軸1本が線分へ課す区間::どの時刻も許す { .. } => {}
                軸1本が線分へ課す区間::入って出る {
                    入る時刻, 出る時刻, ..
                } => {
                    最も遅く入る時刻 = 最も遅く入る時刻.max(*入る時刻);
                    最も早く出る時刻 = 最も早く出る時刻.min(*出る時刻);
                }
            }
        }
        if 最も遅く入る時刻 > 最も早く出る時刻 {
            return None;
        }
        Some(Self {
            軸ごとの区間,
            最も遅く入る時刻,
            最も早く出る時刻,
        })
    }

    pub(super) fn 最も遅く入る時刻(&self) -> f64 {
        self.最も遅く入る時刻
    }

    pub(super) fn 最も早く出る時刻(&self) -> f64 {
        self.最も早く出る時刻
    }

    pub(super) fn 接触の時刻に境界へ載っている側(
        &self, 軸: 直方体自身の座標軸, 接触の時刻: f64
    ) -> Option<直方体の面の向き> {
        self.軸ごとの区間[軸.並びの位置()].時刻に境界へ載っている側(接触の時刻)
    }

    pub(super) fn 接触の時刻に境界へ載っている軸の本数(&self, 接触の時刻: f64) -> usize {
        直方体自身の座標軸::並べる()
            .into_iter()
            .filter(|軸| self.接触の時刻に境界へ載っている側(*軸, 接触の時刻).is_some())
            .count()
    }
}
