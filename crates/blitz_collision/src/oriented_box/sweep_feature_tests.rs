//! カプセルの掃引が直方体のどの特徴に触れるかの反証。軸平行に据えた1辺2メートルの立方体で、面・辺・頂点の
//! 3つの触れ方を見る。
//!
//! 半径と変位は、2次方程式の判別式が平方数になるように選んである。そうすると根が有理数になり、期待値を手で
//! 書ける。位置の比較に幅を置くのは、根が2進で割り切れない値(3分の1)になる組があり、その根に変位を掛けた点が
//! 厳密には元の値へ戻らないためである。

use crate::shape::{直方体の面の向き, 直方体自身の座標軸};

use super::feature::{直方体で当たった特徴, 直方体の辺, 直方体の面, 直方体の頂点};
use super::query_fixture::{三成分が近いことを確かめる, 位置の成分, 方向の成分};
use super::sweep_fixture::{単位の立方体への接触を求める, 掃引の反証が許す幅, 接触を取り出す};

#[test]
fn 面へ垂直に落ちるカプセルは半径だけ手前で止まる() {
    let 接触 = 接触を取り出す(単位の立方体への接触を求める(
        [0.0, 5.0, 0.0],
        [0.0, 7.0, 0.0],
        0.5,
        [0.0, -10.0, 0.0],
    ));
    assert_eq!(接触.動けた割合().値(), 0.35);
    三成分が近いことを確かめる(位置の成分(接触.接触位置()), [0.0, 1.0, 0.0], 掃引の反証が許す幅, "面への接触位置");
    assert_eq!(方向の成分(接触.接触の単位法線()), [0.0, 1.0, 0.0]);
    assert_eq!(
        接触.触れた特徴(),
        直方体で当たった特徴::直方体の面(直方体の面::生成する(直方体自身の座標軸::Y軸, 直方体の面の向き::軸の正の側))
    );
}

#[test]
fn 対角へ進む球は辺の中央に触れる() {
    let 二の平方根 = 2.0_f64.sqrt();
    let 接触 = 接触を取り出す(単位の立方体への接触を求める(
        [4.0, 4.0, 0.0],
        [4.0, 4.0, 0.0],
        二の平方根,
        [-6.0, -6.0, 0.0],
    ));
    assert_eq!(接触.動けた割合().値(), 1.0 / 3.0);
    三成分が近いことを確かめる(位置の成分(接触.接触位置()), [1.0, 1.0, 0.0], 掃引の反証が許す幅, "辺への接触位置");
    三成分が近いことを確かめる(
        方向の成分(接触.接触の単位法線()).map(f64::from),
        [1.0 / 二の平方根, 1.0 / 二の平方根, 0.0],
        1.0e-6,
        "辺への接触の法線",
    );
    assert_eq!(
        接触.触れた特徴(),
        直方体で当たった特徴::直方体の辺(直方体の辺::生成する(
            直方体自身の座標軸::Z軸,
            直方体の面の向き::軸の正の側,
            直方体の面の向き::軸の正の側
        ))
    );
}

#[test]
fn 体対角へ進む球は頂点に触れる() {
    let 三の平方根 = 3.0_f64.sqrt();
    let 接触 = 接触を取り出す(単位の立方体への接触を求める(
        [4.0, 4.0, 4.0],
        [4.0, 4.0, 4.0],
        三の平方根,
        [-6.0, -6.0, -6.0],
    ));
    assert_eq!(接触.動けた割合().値(), 1.0 / 3.0);
    三成分が近いことを確かめる(位置の成分(接触.接触位置()), [1.0, 1.0, 1.0], 掃引の反証が許す幅, "頂点への接触位置");
    三成分が近いことを確かめる(
        方向の成分(接触.接触の単位法線()).map(f64::from),
        [1.0 / 三の平方根; 3],
        1.0e-6,
        "頂点への接触の法線",
    );
    assert_eq!(
        接触.触れた特徴(),
        直方体で当たった特徴::直方体の頂点(直方体の頂点::軸の並びの順の側から生成する(
            [直方体の面の向き::軸の正の側; 3]
        ))
    );
}
