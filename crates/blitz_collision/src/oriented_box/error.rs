//! 任意姿勢の直方体への詳細判定で破れる条件。
//!
//! 形そのものの破れ(中心が有限でない・半分の長さが負である等)はここに入らない。それは`直方体の生成エラー`が
//! 持ち、形を作る地点で拒まれている。ここに在るのは問い合わせの側が渡す点と向き、および求解が導く値の破れである。

use blitz_math::方向エラー;
use thiserror::Error;

use crate::shape::形の局所座標の生成エラー;
use crate::solver::無次元の媒介変数の生成エラー;

/// 任意姿勢の直方体への詳細判定で破れる条件。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 直方体の問い合わせエラー {
    /// 問い合わせの点や、求解が導いた接触の点を局所座標の位置として作れなかった。
    #[error("直方体への問い合わせの点を作れない: {0}")]
    問い合わせの点を作れない(#[from] 形の局所座標の生成エラー),
    /// 線分の媒介変数か掃引で動けた割合が、0以上1以下の有限値でなかった。
    #[error("直方体への問い合わせの媒介変数を作れない: {0}")]
    問い合わせの媒介変数を作れない(#[from] 無次元の媒介変数の生成エラー),
    /// 求めた接触の向きを単位方向へ狭められなかった。
    #[error("直方体への接触の単位法線を作れない: {0}")]
    接触の単位法線を作れない(#[from] 方向エラー),
    /// 接触の向きの長さが0であり、単位方向として定まらなかった。
    #[error("直方体への接触の単位法線が長さ0で定まらない")]
    接触の単位法線が定まらない,
    /// カプセルの半径が0以下か、有限でない値だった。
    #[error("カプセルの半径が正の有限値でない")]
    カプセルの半径が正の有限値でない,
    /// カプセルの半径が、係数の桁あふれを避けるために課した座標の絶対値の上限を越えていた。
    #[error("カプセルの半径が形の座標の絶対値の上限を越えている")]
    カプセルの半径が上限を越えている,
}
