//! 直方体の面と軸の端の接触。触れるのは面が乗る平面と、軸の端に置いた半径の球だけである。
//!
//! 球と平面の隔たりは時刻の1次式であるから、隔たりが半径に等しくなる時刻も1次で決まる。それでも2乗した形の
//! 方程式で解くのは、面の表からも裏からも触れうるためである。1次式のまま解くと符号ごとに2本の式になる。
//! 2乗した式の2次の係数は変位の法線成分の2乗であり、法線と垂直に動く掃引では0になって1次式へ退化する。
//!
//! 平面は面より広いため、根の時刻での接触点が面の四角形の内側に無ければその根を捨てる。
//! 捨てた接触は、面ではなく辺か頂点の候補が答える。

use crate::solver::掃引の2次方程式;
use crate::solver::軸の端;

use super::error::直方体の問い合わせエラー;
use super::feature::{直方体で当たった特徴, 直方体の面};
use super::sweep_place::{直方体で触れた場所, 軸と特徴の最近接};
use super::sweep_solver::カプセルと直方体の接触の求解;

impl カプセルと直方体の接触の求解<'_> {
    pub(super) fn 面と軸の端の方程式を組む(&self, 端: 軸の端, 面: 直方体の面) -> 掃引の2次方程式 {
        let 法線 = self.幾何().面の外向きの単位向きを求める(面);
        let 中央 = self.幾何().面の中央の位置を求める(面);
        掃引の2次方程式::平面と球の隔たりから組む(
            self.基準の点から時刻の軸の端への変位(中央, 端, 0.0).内積(法線),
            self.掃引の変位().内積(法線),
            self.半径の二乗(),
        )
    }

    // 時刻での、面と軸の端の最近接。球の中心を平面へ落とした点が面の四角形の外にあるなら、
    // その点は面での接触ではないため値なしを返す。
    pub(super) fn 面と軸の端の最近接を求める(
        &self,
        端: 軸の端,
        面: 直方体の面,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, 直方体の問い合わせエラー> {
        let 法線 = self.幾何().面の外向きの単位向きを求める(面);
        let 中央から軸へ = self.基準の点から時刻の軸の端への変位(self.幾何().面の中央の位置を求める(面), 端, 時刻);
        let 符号付きの隔たり = 中央から軸へ.内積(法線);
        let 接触位置 = self
            .時刻の軸の端の位置(端, 時刻)?
            .変位だけ進んだ位置を求める(法線.実数倍する(-符号付きの隔たり))?;
        if !self.幾何().面の上の点が内側にあるか(面, 接触位置) {
            return Ok(None);
        }
        Ok(Some(軸と特徴の最近接::生成する(
            符号付きの隔たり * 符号付きの隔たり,
            直方体で触れた場所::生成する(接触位置, 法線.実数倍する(符号付きの隔たり), 直方体で当たった特徴::直方体の面(面)),
        )))
    }
}
