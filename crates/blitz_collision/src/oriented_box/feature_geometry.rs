//! 直方体の特徴が局所座標系のどこに在ってどちらを向いているかを読む工程。受け取るのは面・辺・頂点のどれかで
//! あり、返すのはその位置と向きである。触れるのは倍精度の幾何が公開する中心・軸・半分の長さだけである。
//!
//! 形の表現と別のモジュールへ置くのは、面の代表点や辺の変位が詳細判定のためだけに要る値であり、形を焼き込む側も
//! 粗い選別の側もこれらを使わないためである。形の側が持つと、形の型が判定の都合で太る。
//!
//! 特徴の外向きの向きを正さずに返すのは、正す割り算を答えを組む1箇所へ寄せるためである。辺と頂点の向きは
//! 直交する2本または3本の単位軸の和であるから、長さはそれぞれ2の平方根と3の平方根になる。
//!
//! 特徴の代表の点(面の中央・頂点・辺の始点)を読むのは`feature_place.rs`である。位置と向きを分けるのは、
//! 向きを線分の交差も掃引も使うのに対し、代表の点を使うのが掃引だけであるためである。

use crate::shape::{
    任意姿勢の直方体の倍精度の幾何, 形の局所座標の位置, 形の局所座標の変位, 直方体自身の座標軸
};

use super::feature::{直方体で当たった特徴, 直方体の面};

impl 任意姿勢の直方体の倍精度の幾何 {
    // 中心からその点へ向かう変位を、指定した軸へ射影した長さ。直方体の局所座標へ写した点の1成分である。
    pub(super) fn 中心から見た軸に沿った隔たりを求める(
        &self, 点: 形の局所座標の位置, 軸: 直方体自身の座標軸
    ) -> f64 {
        self.中心().終点までの変位を求める(点).内積(self.軸に沿った単位向き(軸))
    }

    // 面の外側を向く長さ1の変位。接触点集合の切り抜きも参照面の向きとしてこれを読むため、クレートの中へ開く。
    pub(crate) fn 面の外向きの単位向きを求める(&self, 面: 直方体の面) -> 形の局所座標の変位 {
        self.軸に沿った単位向き(面.軸()).実数倍する(面.側().符号())
    }

    // 特徴の外側を向く変位。面は長さ1、辺は2の平方根、頂点は3の平方根の長さになる。
    pub(super) fn 特徴の外向きの向きを求める(&self, 特徴: 直方体で当たった特徴) -> 形の局所座標の変位 {
        match 特徴 {
            直方体で当たった特徴::直方体の面(面) => self.面の外向きの単位向きを求める(面),
            直方体で当たった特徴::直方体の辺(辺) => 直方体自身の座標軸::並べる()
                .into_iter()
                .filter_map(|軸| {
                    辺.軸ごとの側(軸)
                        .map(|側| self.面の外向きの単位向きを求める(直方体の面::生成する(軸, 側)))
                })
                .fold(形の局所座標の変位::零(), 形の局所座標の変位::加える),
            直方体で当たった特徴::直方体の頂点(頂点) => 直方体自身の座標軸::並べる()
                .into_iter()
                .map(|軸| self.面の外向きの単位向きを求める(直方体の面::生成する(軸, 頂点.軸ごとの側(軸))))
                .fold(形の局所座標の変位::零(), 形の局所座標の変位::加える),
        }
    }
}
