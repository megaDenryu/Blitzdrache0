//! 線分が直方体の中に居る時刻の区間から、線分の範囲(0以上1以下)の中でどう入るかを読み取る工程。
//! 受け取るのは区間、返すのは入らないか・始まりから中に在るか・途中で入るかの3つのどれかである。
//!
//! 特徴は、入る時刻に直方体の境界へ載っている軸の本数から組む。1本なら面、2本なら残る1本に沿った辺、
//! 3本なら頂点である。1本も無いのは、どの軸でも始点が板の内側に居る場合だけであり、そのとき線分は始まりから
//! 直方体の中に在る。そのときの最も遅く入る時刻は負の無限大であるから、始まりから中に在るという答えは
//! 2つの経路で一致する。
//!
//! 数える軸を「入る時刻を決めた軸」に限らないのは、稜へ一点で触れて離れる線分と、境界の上を平行移動して稜から
//! 入る線分が、面ではなく辺に触れているためである。どの軸が境界に載っているかは`segment_span.rs`が答える。

use super::feature::{直方体で当たった特徴, 直方体の辺, 直方体の面, 直方体の頂点};
use super::segment_span::線分が直方体の中に居る時刻の区間;
use crate::shape::直方体自身の座標軸;

pub(super) enum 線分の中で直方体へ入る様子 {
    線分の中では入らない,
    始まりから中に在る,
    途中で入る {
        入る時刻: f64,
        入る特徴: 直方体で当たった特徴,
    },
}

impl 線分が直方体の中に居る時刻の区間 {
    pub(super) fn 線分の中で入る様子を求める(&self) -> 線分の中で直方体へ入る様子 {
        if self.最も早く出る時刻() < 0.0 || self.最も遅く入る時刻() > 1.0 {
            return 線分の中で直方体へ入る様子::線分の中では入らない;
        }
        if self.最も遅く入る時刻() <= 0.0 {
            return 線分の中で直方体へ入る様子::始まりから中に在る;
        }
        let 入る時刻 = self.最も遅く入る時刻();
        match self.接触の時刻に境界へ載っている特徴を求める(入る時刻) {
            Some(入る特徴) => 線分の中で直方体へ入る様子::途中で入る { 入る時刻, 入る特徴 },
            None => 線分の中で直方体へ入る様子::始まりから中に在る,
        }
    }

    fn 接触の時刻に境界へ載っている特徴を求める(&self, 接触の時刻: f64) -> Option<直方体で当たった特徴> {
        match self.接触の時刻に境界へ載っている軸の本数(接触の時刻) {
            1 => self.境界に載っている1本の軸から面を組む(接触の時刻),
            2 => self.境界に載っている2本の軸から辺を組む(接触の時刻),
            3 => self.境界に載っている3本の軸から頂点を組む(接触の時刻),
            _ => None,
        }
    }

    fn 境界に載っている1本の軸から面を組む(&self, 接触の時刻: f64) -> Option<直方体で当たった特徴> {
        直方体自身の座標軸::並べる().into_iter().find_map(|軸| {
            self.接触の時刻に境界へ載っている側(軸, 接触の時刻)
                .map(|側| 直方体で当たった特徴::直方体の面(直方体の面::生成する(軸, 側)))
        })
    }

    fn 境界に載っている2本の軸から辺を組む(&self, 接触の時刻: f64) -> Option<直方体で当たった特徴> {
        let 沿う軸 = 直方体自身の座標軸::並べる()
            .into_iter()
            .find(|軸| self.接触の時刻に境界へ載っている側(*軸, 接触の時刻).is_none())?;
        Some(直方体で当たった特徴::直方体の辺(直方体の辺::生成する(
            沿う軸,
            self.接触の時刻に境界へ載っている側(沿う軸.次の軸(), 接触の時刻)?,
            self.接触の時刻に境界へ載っている側(沿う軸.次の軸().次の軸(), 接触の時刻)?,
        )))
    }

    fn 境界に載っている3本の軸から頂点を組む(&self, 接触の時刻: f64) -> Option<直方体で当たった特徴> {
        let x側 = self.接触の時刻に境界へ載っている側(直方体自身の座標軸::X軸, 接触の時刻)?;
        let y側 = self.接触の時刻に境界へ載っている側(直方体自身の座標軸::Y軸, 接触の時刻)?;
        let z側 = self.接触の時刻に境界へ載っている側(直方体自身の座標軸::Z軸, 接触の時刻)?;
        Some(直方体で当たった特徴::直方体の頂点(
            直方体の頂点::軸の並びの順の側から生成する([x側, y側, z側]),
        ))
    }
}
