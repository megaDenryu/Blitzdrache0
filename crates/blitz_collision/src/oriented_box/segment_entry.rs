//! 線分が直方体の中に居る時刻の区間から、線分の範囲(0以上1以下)の中でどう入るかを読み取る工程。
//! 受け取るのは区間、返すのは入らないか・始まりから中に在るか・途中で入るかの3つのどれかである。
//!
//! 入る時刻を決めた軸の本数から特徴を組む。1本なら面、2本なら残る1本に沿った辺、3本なら頂点である。
//! 1本も無いのは、どの軸でも始点が板の中に居る場合だけであり、そのとき線分は始まりから直方体の中に在る。
//! そのときの最も遅く入る時刻は負の無限大であるから、始まりから中に在るという答えは2つの経路で一致する。

use super::feature::{直方体で当たった特徴, 直方体の辺, 直方体の面, 直方体の頂点};
use super::segment_span::線分が直方体の中に居る時刻の区間;
use crate::shape::直方体自身の座標軸;

pub(super) enum 線分の中で直方体へ入る様子 {
    線分の中では入らない,
    始まりから中に在る,
    途中で入る {
        入る時刻: f64,
        入る特徴: 直方体で当たった特徴,
    },
}

impl 線分が直方体の中に居る時刻の区間 {
    pub(super) fn 線分の中で入る様子を求める(&self) -> 線分の中で直方体へ入る様子 {
        if self.最も早く出る時刻() < 0.0 || self.最も遅く入る時刻() > 1.0 {
            return 線分の中で直方体へ入る様子::線分の中では入らない;
        }
        if self.最も遅く入る時刻() <= 0.0 {
            return 線分の中で直方体へ入る様子::始まりから中に在る;
        }
        match self.入る時刻を決めた特徴を求める() {
            Some(入る特徴) => 線分の中で直方体へ入る様子::途中で入る {
                入る時刻: self.最も遅く入る時刻(),
                入る特徴,
            },
            None => 線分の中で直方体へ入る様子::始まりから中に在る,
        }
    }

    fn 入る時刻を決めた特徴を求める(&self) -> Option<直方体で当たった特徴> {
        match self.入る時刻を決めた軸の本数() {
            1 => self.入る時刻を決めた面を求める(),
            2 => self.入る時刻を決めた辺を求める(),
            3 => self.入る時刻を決めた頂点を求める(),
            _ => None,
        }
    }

    fn 入る時刻を決めた面を求める(&self) -> Option<直方体で当たった特徴> {
        直方体自身の座標軸::並べる().into_iter().find_map(|軸| {
            self.入る時刻を決めた側(軸)
                .map(|側| 直方体で当たった特徴::直方体の面(直方体の面::生成する(軸, 側)))
        })
    }

    fn 入る時刻を決めた辺を求める(&self) -> Option<直方体で当たった特徴> {
        let 沿う軸 = 直方体自身の座標軸::並べる()
            .into_iter()
            .find(|軸| self.入る時刻を決めた側(*軸).is_none())?;
        Some(直方体で当たった特徴::直方体の辺(直方体の辺::生成する(
            沿う軸,
            self.入る時刻を決めた側(沿う軸.次の軸())?,
            self.入る時刻を決めた側(沿う軸.次の軸().次の軸())?,
        )))
    }

    fn 入る時刻を決めた頂点を求める(&self) -> Option<直方体で当たった特徴> {
        let x側 = self.入る時刻を決めた側(直方体自身の座標軸::X軸)?;
        let y側 = self.入る時刻を決めた側(直方体自身の座標軸::Y軸)?;
        let z側 = self.入る時刻を決めた側(直方体自身の座標軸::Z軸)?;
        Some(直方体で当たった特徴::直方体の頂点(
            直方体の頂点::軸の並びの順の側から生成する([x側, y側, z側]),
        ))
    }
}
