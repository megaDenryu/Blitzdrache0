//! カプセルと直方体の接触の求解: 掃引するカプセル1つと直方体の倍精度の幾何1つを受け取り、
//! 「掃引の途中で最初に触れる接触」と「掃引の始まりで最も近い特徴」の2つに答える操作サービスである。
//! カプセルと幾何をコンストラクタで受け取って保持するため、どの問いの署名にも幾何が現れない。
//!
//! 2つの問いを1つの型が持つのは、どちらも同じ72通りの候補を同じ順に数え、同じ最近接の工程を通るためである。
//! 掃引の始まりで既に半径以内に居るなら動ける割合は0であり、そのときの法線は最も近い特徴から導く。
//! これは線分の問い合わせが「始点が中に在るなら交差時刻0」とした設計と同じ考えである。

use crate::shape::{任意姿勢の直方体の倍精度の幾何, 形を掃引するカプセル};
use crate::solver::最も小さい量の候補だけを覚える器;

use super::error::直方体の問い合わせエラー;
use super::sweep_candidate::直方体との接触の特徴の候補;
use super::sweep_place::{触れ始める候補, 軸と特徴の最近接};
use crate::solver::掃引で動けた割合;

pub(super) struct カプセルと直方体の接触の求解<'掃引> {
    カプセル: &'掃引 形を掃引するカプセル,
    幾何: &'掃引 任意姿勢の直方体の倍精度の幾何,
}

impl<'掃引> カプセルと直方体の接触の求解<'掃引> {
    pub(super) fn 生成する(
        カプセル: &'掃引 形を掃引するカプセル, 幾何: &'掃引 任意姿勢の直方体の倍精度の幾何
    ) -> Self {
        Self { カプセル, 幾何 }
    }

    pub(super) fn カプセル(&self) -> &形を掃引するカプセル {
        self.カプセル
    }

    pub(super) fn 幾何(&self) -> &任意姿勢の直方体の倍精度の幾何 {
        self.幾何
    }

    // 掃引の途中で最初に触れる接触。どの候補も触れないなら値なしを返す。
    pub(super) fn 掃引の途中で最初に触れる接触を求める(
        &self,
    ) -> Result<Option<触れ始める候補>, 直方体の問い合わせエラー> {
        let mut 最小 = 最も小さい量の候補だけを覚える器::まだ何も無い状態から始める();
        for 候補 in 直方体との接触の特徴の候補::並べる() {
            if let Some(触れ始める) = self.候補が最初に触れる時刻を求める(候補)? {
                最小.候補を1つ数える(触れ始める.動けた割合().値(), 触れ始める);
            }
        }
        Ok(最小.覚えている候補を取り出す())
    }

    // 掃引の始まりで、カプセルの軸に最も近い特徴とその隔たり。呼び出し側はこの隔たりを半径と比べ、
    // 半径以下なら動く前から触れていたものとして扱う。
    pub(super) fn 掃引の始まりで最も近い特徴を求める(
        &self,
    ) -> Result<Option<軸と特徴の最近接>, 直方体の問い合わせエラー> {
        let mut 最小 = 最も小さい量の候補だけを覚える器::まだ何も無い状態から始める();
        for 候補 in 直方体との接触の特徴の候補::並べる() {
            if let Some(最近接) = self.候補の最近接を求める(候補, 0.0)? {
                最小.候補を1つ数える(最近接.隔たりの二乗(), 最近接);
            }
        }
        Ok(最小.覚えている候補を取り出す())
    }

    // 1つの候補について、掃引の中に在る最小の根を探す。根を割合として受理するのは`掃引で動けた割合`であり、
    // 端をわずかに越えた根はそこで端の正準値へ寄る。寄せた割合で最近接を求め直し、媒介変数が面・辺・軸の
    // 範囲に収まったときだけ候補にする。収まらない根は、平面や直線という直方体やカプセルより広がった形での
    // 接触であり、実際には触れていない。
    fn 候補が最初に触れる時刻を求める(
        &self,
        候補: 直方体との接触の特徴の候補,
    ) -> Result<Option<触れ始める候補>, 直方体の問い合わせエラー> {
        let Some(方程式) = self.候補の方程式を組む(候補) else {
            return Ok(None);
        };
        for 根 in 方程式.根を小さい順に並べる() {
            let Some(動けた割合) = 掃引で動けた割合::根を端へ寄せて受理する(根) else {
                continue;
            };
            if let Some(最近接) = self.候補の最近接を求める(候補, 動けた割合.値())? {
                return Ok(Some(触れ始める候補::生成する(動けた割合, 最近接.場所())));
            }
        }
        Ok(None)
    }
}
