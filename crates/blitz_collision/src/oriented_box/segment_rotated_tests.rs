//! 天頂まわりに45度回した直方体への線分の反証。直方体の回転は単精度の四元数で持つため、期待値を2の平方根で
//! 厳密に書けても、実測との比較には単精度の刻みに見合う幅を置く。
//!
//! 手で解ける組を選んでいる。45度回した直方体では、直方体自身のx軸が世界のx軸と45度をなす。世界のx軸に沿って
//! 進む線分から見ると、直方体自身のx軸に垂直な面は世界のx軸を、中心から半分の長さの2の平方根倍だけ離れた点で
//! 横切る。したがって半分の長さが1なら、当たる点は世界のxが2の平方根のマイナス倍のところである。
//!
//! 直方体自身のz軸に垂直な面も同じ角度で立っているため、半分の長さを揃えると2つの面が同じ時刻に入る。
//! それでは軸の並びの丸めのわずかな違いが面と辺の答えを分けるため、z軸の半分の長さを3にして面を1つに決める。

use crate::shape::{直方体の面の向き, 直方体自身の座標軸};

use super::feature::{直方体で当たった特徴, 直方体の面};
use super::query_fixture::{
    三成分が近いことを確かめる, 位置の成分, 天頂まわりの8分の1回転, 方向の成分, 直方体を作る, 線分を作る
};
use super::segment_hit::{直方体への最初の当たり, 線分が直方体に最初に当たる点};
use super::segment_query::直方体の線分の問い合わせ;

// 期待値と実測の隔たりに許す幅。直方体の回転は単精度の四元数で持つため、45度そのものが単精度で表せる角へ
// 丸まる。この丸めは相対で1000万分の1の程度であり、5メートルの座標では100万分の1メートルに満たない。
// 倍精度の正規化と回転行列の組み立てが足す丸めはこれよりさらに10の9乗倍小さい。
const 許容: f64 = 1.0e-6;

fn 回した箱の当たりを求める(始点: [f64; 3], 終点: [f64; 3]) -> 線分が直方体に最初に当たる点 {
    let 直方体 = 直方体を作る([0.0, 0.0, 0.0], 天頂まわりの8分の1回転(), [1.0, 1.0, 3.0]);
    let 線分 = 線分を作る(始点, 終点);
    match 直方体の線分の問い合わせ::直方体から生成する(&直方体).線分が直方体に最初に当たる点を求める(&線分)
    {
        Ok(答え) => 答え,
        Err(誤り) => panic!("線分の問い合わせが失敗した: {誤り}"),
    }
}

fn 当たりを取り出す(答え: 線分が直方体に最初に当たる点) -> 直方体への最初の当たり {
    match 答え {
        線分が直方体に最初に当たる点::直方体に当たる(当たり) => 当たり,
        線分が直方体に最初に当たる点::直方体に当たらない => panic!("当たるはずの線分が当たらなかった"),
    }
}

#[test]
fn 四十五度回した箱の面へ当たる点は二の平方根の位置になる() {
    let 当たり = 当たりを取り出す(回した箱の当たりを求める([-5.0, 0.0, 0.0], [5.0, 0.0, 0.0]));
    let 二の平方根 = 2.0_f64.sqrt();
    assert!(
        (当たり.交差時刻().値() - (5.0 - 二の平方根) / 10.0).abs() <= 許容,
        "交差時刻が期待から離れている: {}",
        当たり.交差時刻().値()
    );
    三成分が近いことを確かめる(位置の成分(当たり.交差位置()), [-二の平方根, 0.0, 0.0], 許容, "交差位置");
}

#[test]
fn 四十五度回した箱の面の法線は二の平方根の半分の成分になる() {
    let 当たり = 当たりを取り出す(回した箱の当たりを求める([-5.0, 0.0, 0.0], [5.0, 0.0, 0.0]));
    let 二の平方根の半分 = 2.0_f64.sqrt() / 2.0;
    三成分が近いことを確かめる(
        方向の成分(当たり.接触面の単位法線()).map(f64::from),
        [-二の平方根の半分, 0.0, 二の平方根の半分],
        1.0e-6,
        "面に当たった法線",
    );
    assert_eq!(
        当たり.当たった特徴(),
        直方体で当たった特徴::直方体の面(直方体の面::生成する(直方体自身の座標軸::X軸, 直方体の面の向き::軸の負の側))
    );
}

#[test]
fn 回した箱の中から始まる線分は最も近い面の法線で返る() {
    let 当たり = 当たりを取り出す(回した箱の当たりを求める([0.5, 0.0, 0.0], [10.0, 0.0, 0.0]));
    let 二の平方根の半分 = 2.0_f64.sqrt() / 2.0;
    assert_eq!(当たり.交差時刻().値(), 0.0);
    assert_eq!(位置の成分(当たり.交差位置()), [0.5, 0.0, 0.0]);
    三成分が近いことを確かめる(
        方向の成分(当たり.接触面の単位法線()).map(f64::from),
        [二の平方根の半分, 0.0, -二の平方根の半分],
        1.0e-6,
        "中から始まった線分の法線",
    );
}

#[test]
fn 同じ入力を二度評価しても答えのビット列が一致する() {
    let 一度目 = 当たりを取り出す(回した箱の当たりを求める([-5.0, 0.25, 0.5], [5.0, 0.25, 0.5]));
    let 二度目 = 当たりを取り出す(回した箱の当たりを求める([-5.0, 0.25, 0.5], [5.0, 0.25, 0.5]));
    assert_eq!(一度目.交差時刻().値().to_bits(), 二度目.交差時刻().値().to_bits());
    for 軸 in 0usize..3 {
        assert_eq!(位置の成分(一度目.交差位置())[軸].to_bits(), 位置の成分(二度目.交差位置())[軸].to_bits());
        assert_eq!(
            方向の成分(一度目.接触面の単位法線())[軸].to_bits(),
            方向の成分(二度目.接触面の単位法線())[軸].to_bits()
        );
    }
    assert_eq!(一度目.当たった特徴(), 二度目.当たった特徴());
}
