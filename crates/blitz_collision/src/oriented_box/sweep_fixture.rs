//! カプセルの掃引の反証が共有する材料。単位の立方体へ掃引を投げる入口と、答えから接触を取り出す読み取りを持つ。
//!
//! 直方体を1辺2メートルの立方体に固定するのは、期待値の手計算が半分の長さ1を前提に書かれているためである。
//! 回転は恒等であり、直方体自身の軸が局所座標系の軸とそのまま重なる。

use blitz_math::クォータニオン;

use super::query_fixture::{カプセルを作る, 直方体を作る};
use super::sweep_contact::{カプセルが直方体に最初に触れる点, 掃引したカプセルの直方体への接触};
use super::sweep_query::直方体のカプセルの掃引の問い合わせ;

// 位置と法線の比較に許す幅。根が2進で割り切れない組でも、時刻から位置を組み直す誤差はこの幅に収まる。
pub(super) const 掃引の反証が許す幅: f64 = 1.0e-12;

pub(super) fn 単位の立方体への接触を求める(
    軸の始点: [f64; 3],
    軸の終点: [f64; 3],
    半径: f64,
    掃引の変位: [f64; 3],
) -> カプセルが直方体に最初に触れる点 {
    let 直方体 = 直方体を作る([0.0, 0.0, 0.0], クォータニオン::恒等(), [1.0, 1.0, 1.0]);
    let カプセル = カプセルを作る(軸の始点, 軸の終点, 半径, 掃引の変位);
    match 直方体のカプセルの掃引の問い合わせ::直方体から生成する(&直方体).カプセルが直方体に最初に触れる点を求める(&カプセル)
    {
        Ok(答え) => 答え,
        Err(誤り) => panic!("掃引の問い合わせが失敗した: {誤り}"),
    }
}

pub(super) fn 接触を取り出す(答え: カプセルが直方体に最初に触れる点) -> 掃引したカプセルの直方体への接触 {
    match 答え {
        カプセルが直方体に最初に触れる点::直方体に触れる(接触) => 接触,
        カプセルが直方体に最初に触れる点::直方体に触れない => panic!("触れるはずのカプセルが触れなかった"),
    }
}
