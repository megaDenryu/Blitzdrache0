//! 直方体の特徴が局所座標系のどこに在るかを読む工程。受け取るのは面・辺・頂点のどれかであり、返すのは
//! 代表の点と、辺については伸びる向きの変位である。触れるのは倍精度の幾何が公開する中心・軸・半分の長さだけである。
//!
//! 特徴の向きを読む工程(`feature_geometry.rs`)と別に置くのは、こちらが掃引の求解だけで要るためである。
//! 線分の交差は軸への射影だけで解けるため、面の代表点も辺の変位も使わない。
//!
//! 位置を有限性の検査を通さずに組むのは、中心と半分の長さが座標の上限に収まり、軸の長さが1であることから、
//! どの代表点も成分の絶対値が上限の4倍を越えないためである。

use crate::shape::{
    任意姿勢の直方体の倍精度の幾何, 形の局所座標の位置, 形の局所座標の変位, 直方体自身の座標軸
};

use super::feature::{直方体の辺, 直方体の面, 直方体の頂点};

impl 任意姿勢の直方体の倍精度の幾何 {
    // 面の中央の点。平面と球の方程式が使う、平面の上の基準の点である。
    pub(super) fn 面の中央の位置を求める(&self, 面: 直方体の面) -> 形の局所座標の位置 {
        let 中心から面へ = self
            .面の外向きの単位向きを求める(面)
            .実数倍する(self.軸に沿った半分の長さのメートル(面.軸()));
        self.中心().検査済みの変位だけ進んだ位置を求める(中心から面へ)
    }

    // 頂点の位置。3軸それぞれの側へ半分の長さだけ進んだ点である。
    pub(super) fn 頂点の位置を求める(&self, 頂点: 直方体の頂点) -> 形の局所座標の位置 {
        let 中心から頂点へ = 直方体自身の座標軸::並べる().into_iter().fold(形の局所座標の変位::零(), |累計, 軸| {
            累計.加える(
                self.軸に沿った単位向き(軸)
                    .実数倍する(頂点.軸ごとの側(軸).符号() * self.軸に沿った半分の長さのメートル(軸)),
            )
        });
        self.中心().検査済みの変位だけ進んだ位置を求める(中心から頂点へ)
    }

    // 辺の始点。沿う軸について負の側に在る頂点である。
    pub(super) fn 辺の始点の位置を求める(&self, 辺: 直方体の辺) -> 形の局所座標の位置 {
        self.頂点の位置を求める(辺.始点の頂点を求める())
    }

    // 辺の始点から終点へ向かう変位。沿う軸の向きへ、その軸の長さ(半分の長さの2倍)だけ進む。
    pub(super) fn 辺の変位を求める(&self, 辺: 直方体の辺) -> 形の局所座標の変位 {
        self.軸に沿った単位向き(辺.沿う軸())
            .実数倍する(2.0 * self.軸に沿った半分の長さのメートル(辺.沿う軸()))
    }

    // 面の平面の上に在る点が、面の四角形の内側(辺の上を含む)に在るか。面に垂直でない2本の軸それぞれについて、
    // 中心から見た隔たりが半分の長さに収まるかを見る。
    pub(super) fn 面の上の点が内側にあるか(&self, 面: 直方体の面, 点: 形の局所座標の位置) -> bool {
        [面.軸().次の軸(), 面.軸().次の軸().次の軸()]
            .into_iter()
            .all(|軸| self.中心から見た軸に沿った隔たりを求める(点, 軸).abs() <= self.軸に沿った半分の長さのメートル(軸))
    }
}
