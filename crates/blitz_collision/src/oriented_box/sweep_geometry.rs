//! 掃引の求解が特徴ごとの式を組むときに何度も使う幾何の読み替え。触れるのは保持したカプセルと直方体の幾何だけである。
//!
//! この工程を分けるのは、面・辺・頂点の3つの求解が同じ読み替えを使うためである。読み替えをそれぞれの
//! 求解へ写すと、時刻での軸の位置の作り方が3つに分かれ、同じ時刻で違う位置を指す余地が生まれる。

use crate::shape::{形の局所座標の位置, 形の局所座標の変位};
use crate::solver::軸の端;

use super::sweep_solver::カプセルと直方体の接触の求解;

impl カプセルと直方体の接触の求解<'_> {
    pub(super) fn 半径の二乗(&self) -> f64 {
        self.カプセル().半径のメートル() * self.カプセル().半径のメートル()
    }

    pub(super) fn 掃引の変位(&self) -> 形の局所座標の変位 {
        self.カプセル().掃引の変位()
    }

    // 軸の始点から終点へ向かう変位。長さ0の軸(球)では零になる。
    pub(super) fn 軸の変位(&self) -> 形の局所座標の変位 {
        self.カプセル().軸の変位を求める()
    }

    // 掃引の始まりでの軸の端の位置。
    pub(super) fn 軸の端の位置(&self, 端: 軸の端) -> 形の局所座標の位置 {
        self.カプセル().軸の端点を並べる()[端.並びの位置()]
    }

    // 時刻での軸の端の位置。掃引はカプセル全体を同じだけ動かすため、時刻の1次式である。
    pub(super) fn 時刻の軸の端の位置(
        &self,
        端: 軸の端,
        時刻: f64,
    ) -> Result<形の局所座標の位置, crate::shape::形の局所座標の生成エラー> {
        self.軸の端の位置(端).変位だけ進んだ位置を求める(self.掃引の変位().実数倍する(時刻))
    }

    // 直方体の上の基準の点から、時刻での軸の端へ向かう変位。
    pub(super) fn 基準の点から時刻の軸の端への変位(
        &self,
        基準の点: 形の局所座標の位置,
        端: 軸の端,
        時刻: f64,
    ) -> 形の局所座標の変位 {
        基準の点
            .終点までの変位を求める(self.軸の端の位置(端))
            .加える(self.掃引の変位().実数倍する(時刻))
    }
}
