//! 候補を接触として持つかを、保持したカプセルの掃引の変位から判定する工程。触れるのは求解が保持するカプセルの
//! 掃引の変位と直方体の幾何だけである。始まりから触れている候補(`sweep_query.rs`)と掃引の途中の根
//! (`sweep_solver.rs`)の両方がこの判定を通す。規則そのものは求解の部品が持つ。
//!
//! 接触位置から軸へ向かう変位が零の場所(軸そのものが直方体を貫く場合)は、当たった特徴の外向きの向きで判定する。
//! 答えを組む側が法線に選ぶ向きと同じである。
//! 参照: `crates/blitz_collision/src/solver/approach.rs`

use crate::shape::形の局所座標の変位;
use crate::solver::掃引が面へ向かうかの判定;

use super::sweep_place::直方体で触れた場所;
use super::sweep_solver::カプセルと直方体の接触の求解;

impl カプセルと直方体の接触の求解<'_> {
    pub(super) fn 面へ向かう接触か(&self, 場所: &直方体で触れた場所) -> bool {
        掃引が面へ向かうかの判定::掃引の変位から生成する(self.掃引の変位()).接触として持つか(self.軸へ向かう向きの変位(場所))
    }

    fn 軸へ向かう向きの変位(&self, 場所: &直方体で触れた場所) -> 形の局所座標の変位 {
        if 場所.接触位置から軸への変位().長さの二乗() > 0.0 {
            return 場所.接触位置から軸への変位();
        }
        self.幾何().特徴の外向きの向きを求める(場所.触れた特徴())
    }
}
