//! 直方体の線分の問い合わせ: 始点から終点へ引いた線分が任意姿勢の直方体に最初に当たる点を求める操作サービス。
//! 直方体を倍精度で読み直した幾何をコンストラクタで受け取って保持するため、問い合わせの署名に形が現れない。
//!
//! 1回の問い合わせでヒープを確保しない。持つのは軸ごとの区間3つと、その交差の結果だけである。
//!
//! 方式は、直方体の3本の軸へ線分を射影して軸ごとに板の中に居る時刻の区間を作り、3つの区間を交差させるもので
//! ある。射影は「中心から点への変位と軸の単位向きの内積」であり、これが直方体の局所座標へ写した成分そのもので
//! ある。行列を組んで点を写してから軸平行の箱と比べるのと同じ計算を、成分ごとに1回の内積で行う。

use crate::shape::{任意姿勢の直方体, 任意姿勢の直方体の倍精度の幾何, 直方体自身の座標軸};
use crate::solver::線分の媒介変数;

use super::error::直方体の問い合わせエラー;
use super::feature::直方体で当たった特徴;
use super::segment_entry::線分の中で直方体へ入る様子;
use super::segment_hit::{直方体への最初の当たり, 線分が直方体に最初に当たる点};
use super::segment_span::線分が直方体の中に居る時刻の区間;
use super::segment_through_box::直方体を貫く線分;
use super::slab::軸1本が線分へ課す区間;

/// 任意姿勢の直方体の線分の問い合わせ。直方体の倍精度の幾何を保持し、線分が最初に当たる点を答える操作サービスである。
pub struct 直方体の線分の問い合わせ {
    幾何: 任意姿勢の直方体の倍精度の幾何,
}

impl 直方体の線分の問い合わせ {
    /// 直方体を倍精度で読み直して保持する。読み直しは問い合わせのたびではなく、この生成の1回だけ行う。
    pub fn 直方体から生成する(直方体: &任意姿勢の直方体) -> Self {
        Self {
            幾何: 任意姿勢の直方体の倍精度の幾何::直方体から組む(直方体),
        }
    }

    /// 線分が直方体に最初に当たる点を求める。始点が既に直方体の中にある線分は、交差時刻0で当たったものとして
    /// 返し、その法線は最も近い面から導く。
    pub fn 線分が直方体に最初に当たる点を求める(
        &self,
        線分: &直方体を貫く線分,
    ) -> Result<線分が直方体に最初に当たる点, 直方体の問い合わせエラー> {
        let Some(区間) =
            線分が直方体の中に居る時刻の区間::軸ごとの区間を交差させて求める(self.軸ごとの区間を求める(線分))
        else {
            return Ok(線分が直方体に最初に当たる点::直方体に当たらない);
        };
        match 区間.線分の中で入る様子を求める() {
            線分の中で直方体へ入る様子::線分の中では入らない => Ok(線分が直方体に最初に当たる点::直方体に当たらない),
            線分の中で直方体へ入る様子::始まりから中に在る => {
                let 面 = self.幾何.点に最も近い面を求める(線分.始点());
                self.当たりを組む(線分, 0.0, 直方体で当たった特徴::直方体の面(面))
            }
            線分の中で直方体へ入る様子::途中で入る { 入る時刻, 入る特徴 } => {
                self.当たりを組む(線分, 入る時刻, 入る特徴)
            }
        }
    }

    // 3本の軸それぞれについて、線分がその軸の板の中に居る時刻の区間を求める。
    fn 軸ごとの区間を求める(&self, 線分: &直方体を貫く線分) -> [軸1本が線分へ課す区間; 3] {
        let 始点から終点への変位 = 線分.始点から終点への変位を求める();
        直方体自身の座標軸::並べる().map(|軸| {
            軸1本が線分へ課す区間::隔たりと速度から求める(
                self.幾何.中心から見た軸に沿った隔たりを求める(線分.始点(), 軸),
                始点から終点への変位.内積(self.幾何.軸に沿った単位向き(軸)),
                self.幾何.軸に沿った半分の長さのメートル(軸),
            )
        })
    }

    // 当たりの時刻と特徴から答えを組む。時刻は区間の交差が生む商であり、丸めで0や1をわずかに外れうるため
    // 端へ寄せて受け取る。
    fn 当たりを組む(
        &self,
        線分: &直方体を貫く線分,
        当たる時刻: f64,
        特徴: 直方体で当たった特徴,
    ) -> Result<線分が直方体に最初に当たる点, 直方体の問い合わせエラー> {
        let 交差時刻 = 線分の媒介変数::端へ寄せて生成する(当たる時刻)?;
        Ok(線分が直方体に最初に当たる点::直方体に当たる(
            直方体への最初の当たり::生成する(
                交差時刻,
                線分.線分上の点を求める(交差時刻)?,
                self.幾何.特徴の外向きの単位法線を求める(特徴)?,
                特徴,
            ),
        ))
    }
}
