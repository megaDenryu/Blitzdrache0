//! 線分が直方体に最初に当たった点と、当たらなかったことを表す枝。
//!
//! 当たりが持つのは幾何学的な事実だけである。壁か床か、そこで止まるか滑るかという意味付けは持たない。
//!
//! 接触面の単位法線を単精度の方向で持つのは、直方体の回転そのものが単精度で焼かれており、向きの精度を
//! それ以上上げても形の側の精度を越えられないためである。位置は倍精度のまま返す。位置は原点から遠いほど
//! 単精度の刻みが粗くなり、狭めると当たりの点が形の外へ出うるからである。

use blitz_math::{ローカル, 方向};

use crate::shape::形の局所座標の位置;
use crate::solver::線分の媒介変数;

use super::feature::直方体で当たった特徴;

/// 線分が直方体に最初に当たった点。終点まで当たらなかった枝と、当たりを持つ枝の2つである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 線分が直方体に最初に当たる点 {
    /// 終点まで直方体に当たらなかった。
    直方体に当たらない,
    /// 線分の途中で直方体に当たり、その最初の当たりを持つ。
    直方体に当たる(直方体への最初の当たり),
}

/// 線分が直方体に最初に当たった1つの事実。交差時刻・交差位置・接触面の単位法線・当たった特徴を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 直方体への最初の当たり {
    交差時刻: 線分の媒介変数,
    交差位置: 形の局所座標の位置,
    接触面の単位法線: 方向<ローカル>,
    当たった特徴: 直方体で当たった特徴,
}

impl 直方体への最初の当たり {
    pub(super) fn 生成する(
        交差時刻: 線分の媒介変数,
        交差位置: 形の局所座標の位置,
        接触面の単位法線: 方向<ローカル>,
        当たった特徴: 直方体で当たった特徴,
    ) -> Self {
        Self {
            交差時刻,
            交差位置,
            接触面の単位法線,
            当たった特徴,
        }
    }

    /// 線分の始点を0、終点を1として測った、最初に直方体へ達した時刻。始点が既に直方体の中にある線分では0になる。
    pub fn 交差時刻(&self) -> 線分の媒介変数 {
        self.交差時刻
    }

    /// 線分の上の点として求めた交差の位置。
    pub fn 交差位置(&self) -> 形の局所座標の位置 {
        self.交差位置
    }

    /// 当たった特徴の外側を向く単位方向。面なら面の法線、辺と頂点ならそこに集まる面の法線を足して正した向きである。
    pub fn 接触面の単位法線(&self) -> 方向<ローカル> {
        self.接触面の単位法線
    }

    /// 直方体の面・辺・頂点のどれに当たったか。
    pub fn 当たった特徴(&self) -> 直方体で当たった特徴 {
        self.当たった特徴
    }
}
