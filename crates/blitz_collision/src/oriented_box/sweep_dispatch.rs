//! 候補の種類から、その特徴の方程式と最近接の工程を選ぶ振り分け。担当するのは選ぶことだけであり、
//! 式そのものは面・辺・頂点の求解が持つ。
//!
//! 振り分けを1箇所へ集めるのは、候補の種類を増やしたときに方程式と最近接の片方だけを足す取りこぼしを
//! 型検査で落とすためである。網羅の`match`が2つ並ぶため、枝を1つ足すと両方が同時にコンパイルで失敗する。

use crate::solver::掃引の2次方程式;

use super::error::直方体の問い合わせエラー;
use super::sweep_candidate::直方体との接触の特徴の候補;
use super::sweep_place::軸と特徴の最近接;
use super::sweep_solver::カプセルと直方体の接触の求解;

impl カプセルと直方体の接触の求解<'_> {
    // 候補の接触の時刻が満たす方程式。その候補が成り立たない形(長さ0の軸や辺、平行な2直線)では値なしを返す。
    pub(super) fn 候補の方程式を組む(&self, 候補: 直方体との接触の特徴の候補) -> Option<掃引の2次方程式> {
        match 候補 {
            直方体との接触の特徴の候補::面と軸の端 { 端, 面 } => Some(self.面と軸の端の方程式を組む(端, 面)),
            直方体との接触の特徴の候補::辺と軸の端 { 端, 辺 } => self.辺と軸の端の方程式を組む(端, 辺),
            直方体との接触の特徴の候補::頂点と軸の端 { 端, 頂点 } => Some(self.頂点と軸の端の方程式を組む(端, 頂点)),
            直方体との接触の特徴の候補::辺と軸の内側 { 辺 } => self.辺と軸の内側の方程式を組む(辺),
            直方体との接触の特徴の候補::頂点と軸の内側 { 頂点 } => self.頂点と軸の内側の方程式を組む(頂点),
        }
    }

    // 時刻での、その候補が指す特徴とカプセルの最近接。媒介変数が面・辺・軸の範囲の外にあるなら値なしを返す。
    pub(super) fn 候補の最近接を求める(
        &self,
        候補: 直方体との接触の特徴の候補,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, 直方体の問い合わせエラー> {
        match 候補 {
            直方体との接触の特徴の候補::面と軸の端 { 端, 面 } => self.面と軸の端の最近接を求める(端, 面, 時刻),
            直方体との接触の特徴の候補::辺と軸の端 { 端, 辺 } => self.辺と軸の端の最近接を求める(端, 辺, 時刻),
            直方体との接触の特徴の候補::頂点と軸の端 { 端, 頂点 } => {
                self.頂点と軸の端の最近接を求める(端, 頂点, 時刻)
            }
            直方体との接触の特徴の候補::辺と軸の内側 { 辺 } => self.辺と軸の内側の最近接を求める(辺, 時刻),
            直方体との接触の特徴の候補::頂点と軸の内側 { 頂点 } => {
                self.頂点と軸の内側の最近接を求める(頂点, 時刻)
            }
        }
    }
}
