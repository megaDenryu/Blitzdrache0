//! 直方体への問い合わせの反証が共有する材料。直方体と線分を組む道具と、答えを人が読める組へ落とす読み取りを持つ。
//!
//! 縮尺を1箇所で決めるのは、反証ごとに違う大きさの世界を組んで期待値が食い違うことを防ぐためである。
//! 回転は天頂まわりの8分の1回転(45度)を使う。この回転では直方体自身のx軸とz軸が世界のx軸と45度をなし、
//! 面までの隔たりが2の平方根の倍数という手で書ける値になる。

use blitz_math::{クォータニオン, メートル, ローカル, 位置, 方向};

use crate::shape::{
    任意姿勢の直方体, 形の局所座標の位置, 形の局所座標の変位, 形を掃引するカプセル, 形を貫く線分, 直方体の軸ごとの半分の長さ
};

pub(super) fn 天頂まわりの8分の1回転() -> クォータニオン<ローカル, ローカル> {
    let 半角 = std::f32::consts::FRAC_PI_8;
    match クォータニオン::生成する(0.0, 半角.sin(), 0.0, 半角.cos()) {
        Ok(回転) => 回転,
        Err(誤り) => panic!("試験用の回転を作れなかった: {誤り}"),
    }
}

pub(super) fn 直方体を作る(
    中心: [f32; 3], 回転: クォータニオン<ローカル, ローカル>, 半分: [f32; 3]
) -> 任意姿勢の直方体 {
    let 中心の位置 = 位置::生成する(メートル::生成する(中心[0]), メートル::生成する(中心[1]), メートル::生成する(中心[2]));
    let 半分の長さ = match 直方体の軸ごとの半分の長さ::生成する(半分.map(メートル::生成する)) {
        Ok(値) => 値,
        Err(誤り) => panic!("試験用の半分の長さを作れなかった: {誤り}"),
    };
    match 任意姿勢の直方体::生成する(中心の位置, 回転, 半分の長さ) {
        Ok(直方体) => 直方体,
        Err(誤り) => panic!("試験用の直方体を作れなかった: {誤り}"),
    }
}

pub(super) fn 局所の点(成分: [f64; 3]) -> 形の局所座標の位置 {
    match 形の局所座標の位置::生成する(成分[0], 成分[1], 成分[2]) {
        Ok(位置) => 位置,
        Err(誤り) => panic!("試験用の局所の点を作れなかった: {誤り}"),
    }
}

pub(super) fn 線分を作る(始点: [f64; 3], 終点: [f64; 3]) -> 形を貫く線分 {
    形を貫く線分::生成する(局所の点(始点), 局所の点(終点))
}

pub(super) fn 局所の変位(成分: [f64; 3]) -> 形の局所座標の変位 {
    match 形の局所座標の変位::生成する(成分[0], 成分[1], 成分[2]) {
        Ok(変位) => 変位,
        Err(誤り) => panic!("試験用の局所の変位を作れなかった: {誤り}"),
    }
}

pub(super) fn カプセルを作る(
    軸の始点: [f64; 3],
    軸の終点: [f64; 3],
    半径のメートル: f64,
    掃引の変位: [f64; 3],
) -> 形を掃引するカプセル {
    match 形を掃引するカプセル::生成する(局所の点(軸の始点), 局所の点(軸の終点), 半径のメートル, 局所の変位(掃引の変位))
    {
        Ok(カプセル) => カプセル,
        Err(誤り) => panic!("試験用のカプセルを作れなかった: {誤り}"),
    }
}

pub(super) fn 位置の成分(位置: 形の局所座標の位置) -> [f64; 3] {
    [位置.xのメートル(), 位置.yのメートル(), 位置.zのメートル()]
}

pub(super) fn 方向の成分(方向: 方向<ローカル>) -> [f32; 3] {
    [方向.x(), 方向.y(), 方向.z()]
}

/// 3成分が期待値から許容の幅の中に在ることを確かめる。回転を四元数から組む割り算が倍精度の丸めを通すため、
/// 回った直方体の答えは厳密な等号では書けない。
pub(super) fn 三成分が近いことを確かめる(実測: [f64; 3], 期待: [f64; 3], 許容: f64, 何の値か: &str) {
    for 軸 in 0usize..3 {
        assert!(
            (実測[軸] - 期待[軸]).abs() <= 許容,
            "{何の値か}の軸{軸}が期待から離れている(実測{}、期待{})",
            実測[軸],
            期待[軸]
        );
    }
}
