//! 直方体の1本の軸が線分へ課す時刻の区間。直方体は3本の軸それぞれについて、中心から半分の長さだけ離れた
//! 2枚の平面に挟まれた板であり、線分が直方体の中に居る時刻は3つの板の中に居る時刻の共通部分である。
//!
//! 軸に沿った位置は時刻の1次式であるから、板の中に居る時刻は1つの区間になる。線分がその軸の向きへまったく
//! 動かない場合だけ区間が定まらず、始点が板の中に居るならどの時刻も許し、外に居るならどの時刻も許さない。
//!
//! 入る側を持つのは、答えが直方体のどの面から入ったかを返すためである。軸の正の向きへ進む線分は軸の負の側の
//! 面から入り、負の向きへ進む線分は正の側の面から入る。
//!
//! どの時刻も許す枝が境界に載っている側も持つのは、その軸の向きへ動かない線分が板の境界ちょうどを平行移動
//! しうるためである。それは直方体の表面をなぞる動きであり、区間としては何も課さないが、当たった特徴の一部で
//! ある。この側を捨てると、稜から入る線分が面として返り、法線が実際には触れていない面の向きになる。

use crate::shape::直方体の面の向き;

pub(super) enum 軸1本が線分へ課す区間 {
    どの時刻も許さない,
    どの時刻も許す {
        境界に載っている側: Option<直方体の面の向き>,
    },
    入って出る {
        入る時刻: f64,
        出る時刻: f64,
        入る側: 直方体の面の向き,
    },
}

impl 軸1本が線分へ課す区間 {
    // 軸に沿った始点の隔たり(中心から測る)と、軸に沿った線分の速度(始点から終点への変位の射影)と、
    // その軸の半分の長さから区間を求める。速度は線分の全体を1としたときの値である。
    pub(super) fn 隔たりと速度から求める(始点の隔たり: f64, 速度: f64, 半分の長さ: f64) -> Self {
        if 速度 == 0.0 {
            if 始点の隔たり.abs() > 半分の長さ {
                return Self::どの時刻も許さない;
            }
            return Self::どの時刻も許す {
                境界に載っている側: 動かない軸が板の境界に載っている側を求める(始点の隔たり, 半分の長さ),
            };
        }
        let 負の側の面へ達する時刻 = (-半分の長さ - 始点の隔たり) / 速度;
        let 正の側の面へ達する時刻 = (半分の長さ - 始点の隔たり) / 速度;
        if 速度 > 0.0 {
            Self::入って出る {
                入る時刻: 負の側の面へ達する時刻,
                出る時刻: 正の側の面へ達する時刻,
                入る側: 直方体の面の向き::軸の負の側,
            }
        } else {
            Self::入って出る {
                入る時刻: 正の側の面へ達する時刻,
                出る時刻: 負の側の面へ達する時刻,
                入る側: 直方体の面の向き::軸の正の側,
            }
        }
    }

    // 指定した時刻に線分がこの軸の板の境界へ載っているなら、その側を返す。入る時刻と出る時刻は板の2枚の平面へ
    // 達する時刻そのものであるから、その2つとの厳密な比較でどちらの境界に載っているかが決まる。板が潰れて
    // 入る時刻と出る時刻が並んだ場合は入る側を選び、答えを入力だけで決める。
    pub(super) fn 時刻に境界へ載っている側(&self, 時刻: f64) -> Option<直方体の面の向き> {
        match self {
            Self::どの時刻も許さない => None,
            Self::どの時刻も許す { 境界に載っている側 } => *境界に載っている側,
            Self::入って出る {
                入る時刻, 出る時刻, 入る側
            } => {
                if *入る時刻 == 時刻 {
                    return Some(*入る側);
                }
                if *出る時刻 == 時刻 {
                    return Some(入る側.反対の側());
                }
                None
            }
        }
    }
}

// 軸の向きへ動かない線分が、板の2枚の平面のどちらかにちょうど載っているならその側。板の中に居るだけなら値なしである。
fn 動かない軸が板の境界に載っている側を求める(
    始点の隔たり: f64, 半分の長さ: f64
) -> Option<直方体の面の向き> {
    if 始点の隔たり == 半分の長さ {
        return Some(直方体の面の向き::軸の正の側);
    }
    if 始点の隔たり == -半分の長さ {
        return Some(直方体の面の向き::軸の負の側);
    }
    None
}
