//! 2つの直方体を分けうる軸の目録。面の軸が3本ずつ、辺の向きの組の外積が9本で、合わせて15本である。
//!
//! この15本で尽きる根拠は、2つの凸多面体の差(ミンコフスキー差)の面の法線がそれだけであることである。
//! 差が原点を含まないことと、差のどれかの面の法線が原点を分けることは同じであるから、15本すべてで重なりが
//! 正なら2つの直方体は重なっている。直方体の面は3方向、辺は3方向であり、2つの辺の向きが張る面の法線が
//! その外積である。
//!
//! 2つの辺の向きが平行な組は数えない。その組が張る面が差に存在しないためである。平行な2辺のミンコフスキー
//! 和は線分であって面にならず、外積は零になる。零の向きを軸に選ぶと、どんな2つの形も重なっていると答える。
//!
//! 並びを固定するのは、重なりが等しい軸が複数あるときに答えを入力だけで決めるためである。面の軸を先に置く
//! のは、面で乗った2つの直方体で面の軸と外積の軸が同じ深さになるとき、面の軸を選んで接触点を複数得るためで
//! ある。外積の軸を選ぶと接触点が1つになり、積み重ねた箱が傾く。

use crate::shape::直方体自身の座標軸;

/// 2つの直方体を分けうる軸のどれか1本。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 直方体どうしの分離軸 {
    第1の直方体の面の軸(直方体自身の座標軸),
    第2の直方体の面の軸(直方体自身の座標軸),
    二つの辺の向きの外積の軸 {
        第1の直方体の軸: 直方体自身の座標軸,
        第2の直方体の軸: 直方体自身の座標軸,
    },
}

impl 直方体どうしの分離軸 {
    // 15本を、面の軸・外積の軸の順に並べる。同じ深さの軸が並んだときは先に来たものが残る。
    pub(super) fn 並べる() -> [Self; 15] {
        let 軸 = 直方体自身の座標軸::並べる();
        [
            Self::第1の直方体の面の軸(軸[0]),
            Self::第1の直方体の面の軸(軸[1]),
            Self::第1の直方体の面の軸(軸[2]),
            Self::第2の直方体の面の軸(軸[0]),
            Self::第2の直方体の面の軸(軸[1]),
            Self::第2の直方体の面の軸(軸[2]),
            Self::外積(軸[0], 軸[0]),
            Self::外積(軸[0], 軸[1]),
            Self::外積(軸[0], 軸[2]),
            Self::外積(軸[1], 軸[0]),
            Self::外積(軸[1], 軸[1]),
            Self::外積(軸[1], 軸[2]),
            Self::外積(軸[2], 軸[0]),
            Self::外積(軸[2], 軸[1]),
            Self::外積(軸[2], 軸[2]),
        ]
    }

    fn 外積(第1の直方体の軸: 直方体自身の座標軸, 第2の直方体の軸: 直方体自身の座標軸) -> Self {
        Self::二つの辺の向きの外積の軸 {
            第1の直方体の軸,
            第2の直方体の軸,
        }
    }
}
