//! 参照軸の選択で、外積の軸が僅差で浅いだけのときに面の軸を残すことの反証(Issue #75)。
//!
//! 余白の反証(`box_pair_stack_tests.rs`)と別に置くのは、あちらが「参照面が決まった後に角を残す範囲」を
//! 固定しているのに対し、こちらは「どの軸を参照面にするか」を固定するためである。読む長さも別である。
//! あちらは接触生成の余白を読み、こちらは外積の軸へ切り替える優位幅を読む。
//!
//! **幾何の最小の軸はどの配置でも決まっている。** ここが固定するのは、決まっている最小が外積の軸であっても、
//! その優位が丸めの上界と優位幅の和を超えないうちは接触解法へ面の軸を渡す、という選択の方針である。
//!
//! 材料は塔の第n段と第n+1段が実際に取る配置である。上の立方体を2本の水平軸まわりに1e-3ラジアンずつ捻り、
//! 水平に0.05メートルと0.01メートルずらすと、鉛直に近い外積の軸(第1の立方体のX軸と第2の立方体のZ軸の外積)の
//! 深さが面の軸より9.5e-6メートルだけ浅くなる。塔で導かれる優位幅1.11e-4メートルはこれより大きい。
//! 参照: `crates/blitz_collision/src/contact_set/cross_axis_preference.rs`、`_doc/設計/剛体の状態と接触.md`「判断11」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use crate::oriented_box::直方体で当たった特徴;

use super::box_pair_query::{二つの直方体の重なりの接触点集合, 直方体どうしの接触点集合の問い合わせ};
use super::cross_axis_preference::外積の軸へ切り替える優位幅メートル;
use super::generation_margin::接触生成の余白メートル;
use super::query_fixture::{回転なし, 直方体を作る, 軸まわりの回転};

const 半分の長さ: f32 = 0.5;
const 食い込み: f32 = 0.001;
// 塔の静穏な対で導かれるメートル。余白の静穏の下限と優位幅は同じ式であるため同じ値になる(計測記録の公式値11)。
const 塔の静穏の長さ: f64 = 1.11e-4;
// 高速の対で導かれうる大きさの接触生成の余白であるメートル。優位幅はこの値では動かない。
const 高速の対の余白: f64 = 0.05;
// 2本の水平軸まわりに1e-3ラジアンずつ捻る回転の角度である度。
const 捻りの度: f32 = 0.081_028_47;

fn 塔の余白() -> 接触生成の余白メートル {
    接触生成の余白メートル::生成する(塔の静穏の長さ).unwrap()
}

fn 塔の優位幅() -> 外積の軸へ切り替える優位幅メートル {
    外積の軸へ切り替える優位幅メートル::生成する(塔の静穏の長さ).unwrap()
}

// 面で乗せた同じ大きさの2つの立方体を、2本の水平軸まわりに微小に捻って水平にずらした配置の接触点。
fn 微小に捻って積んだ二つの立方体の接触点(
    余白: 接触生成の余白メートル,
    優位幅: 外積の軸へ切り替える優位幅メートル,
) -> Vec<(直方体で当たった特徴, 直方体で当たった特徴)> {
    let 下 = 直方体を作る([0.0, 半分の長さ, 0.0], 回転なし(), [半分の長さ; 3]);
    let 上 = 直方体を作る(
        [0.05, 半分の長さ * 3.0 - 食い込み, 0.01],
        軸まわりの回転([1.0, 0.0, 1.0], 捻りの度),
        [半分の長さ; 3],
    );
    接触点の特徴を並べる(&下, &上, 余白, 優位幅)
}

// 45度捻った2本の角柱を辺どうしで交差させた配置の接触点。深さの差が優位幅を桁で超える材料である。
fn 辺どうしで交差する二つの角柱の接触点(
    余白: 接触生成の余白メートル,
    優位幅: 外積の軸へ切り替える優位幅メートル,
) -> Vec<(直方体で当たった特徴, 直方体で当たった特徴)> {
    let 下 = 直方体を作る([0.0, 0.0, 0.0], 軸まわりの回転([1.0, 0.0, 0.0], 45.0), [2.0, 0.25, 0.25]);
    let 上 = 直方体を作る([0.0, 0.697_106_8, 0.0], 軸まわりの回転([0.0, 0.0, 1.0], 45.0), [0.25, 0.25, 2.0]);
    接触点の特徴を並べる(&下, &上, 余白, 優位幅)
}

fn 接触点の特徴を並べる(
    第1: &crate::shape::任意姿勢の直方体,
    第2: &crate::shape::任意姿勢の直方体,
    余白: 接触生成の余白メートル,
    優位幅: 外積の軸へ切り替える優位幅メートル,
) -> Vec<(直方体で当たった特徴, 直方体で当たった特徴)> {
    let 問い =
        直方体どうしの接触点集合の問い合わせ::二つの直方体と余白と優位幅から生成する(第1, 第2, 余白, 優位幅);
    let 二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) = 問い.二つの直方体の重なりの接触点集合を求める().unwrap()
    else {
        panic!("重なっているはずの2つの直方体が離れていると答えた");
    };
    集合
        .接触解法の候補点を順に並べる()
        .map(|点| (点.特徴の識別().第1の直方体の特徴(), 点.特徴の識別().第2の直方体の特徴()))
        .collect()
}

#[test]
fn 微小に捻って積んだ立方体は優位幅の内側の差では面の軸を参照面にする() {
    let 接触点 = 微小に捻って積んだ二つの立方体の接触点(塔の余白(), 塔の優位幅());
    assert!(接触点.len() >= 3, "面の軸が選ばれていれば3点以上になる(実測{}点)", 接触点.len());
    assert!(
        接触点.iter().any(|(下, _)| matches!(下, 直方体で当たった特徴::直方体の面(_))),
        "参照面が面の軸でない(実測{接触点:?})"
    );
}

#[test]
fn 優位幅を持たない対照では同じ配置で外積の軸が選ばれて接触点が一点になる() {
    let 接触点 = 微小に捻って積んだ二つの立方体の接触点(塔の余白(), 外積の軸へ切り替える優位幅メートル::優位幅を持たない());
    assert_eq!(接触点.len(), 1, "優位幅を外した対照で接触点が1つに落ちていない(実測{接触点:?})");
}

#[test]
fn 辺どうしで交差する二つの角柱では優位幅があっても外積の軸が選ばれる() {
    for 接触点 in [
        辺どうしで交差する二つの角柱の接触点(塔の余白(), 塔の優位幅()),
        辺どうしで交差する二つの角柱の接触点(接触生成の余白メートル::生成する(高速の対の余白).unwrap(), 塔の優位幅()),
    ] {
        assert_eq!(接触点.len(), 1, "辺どうしの交差で接触点が1つでない(実測{接触点:?})");
        for (第1, 第2) in 接触点 {
            assert!(
                matches!(第1, 直方体で当たった特徴::直方体の辺(_)),
                "第1の角柱の特徴が辺でない(実測{第1:?})"
            );
            assert!(
                matches!(第2, 直方体で当たった特徴::直方体の辺(_)),
                "第2の角柱の特徴が辺でない(実測{第2:?})"
            );
        }
    }
}
