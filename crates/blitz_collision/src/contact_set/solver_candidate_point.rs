//! 接触解法の候補点: 接触点集合が持つ1点で、2つの形それぞれの表面の点と、共有の単位法線に沿った符号付き貫通量と、
//! どの特徴どうしで生まれたかの識別を持つ。
//!
//! 接触点と別の語を立てているのは、この点が接触生成の余白の内側で離れていること(符号付き貫通量が負であること)を
//! 許すためである。幾何の事実としての接触点は「2つの形が触れ合う1点」であり、離れている点はそれに当たらない。
//! 符号付き貫通量が0以上の候補点が接触点であり、その判定は `実際に触れているか` が答える。離れている候補点を残す
//! 理由は `crates/blitz_collision/src/contact_set/generation_margin.rs` にある。
//!
//! 2つの形それぞれの上の点を両方持つのは、剛体の解法が接触点の力を掛ける腕の長さを物体ごとの重心から測る
//! ためであり、片方だけを持たせると受け取った側が法線と符号付き貫通量から組み直すことになる。組み直しは倍精度の
//! 演算をもう一度通すため、この層が倍精度で求めた点と最終桁が食い違う。
//!
//! 不変条件: 第2の形の上の位置は、第1の形の上の位置から共有の単位法線の向きへ符号付き貫通量だけ戻った点である。
//! 面での接触ではこれが厳密に成り立ち、辺どうしの接触では2本の辺の最近接点をそのまま持つため、丸めの
//! 範囲で成り立つ。離れている候補点では戻る長さが負であり、第1の形の上の位置より法線の手前へ戻る。
//! 共有の単位法線は候補点ごとには持たず、接触点集合が1つだけ持つ。
//!
//! 特徴の識別は、次の刻みで同じ接触を見つけ直すための綴りである。この層は追跡そのものを行わない。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断6: 幾何問い合わせの能力一覧」

use crate::shape::形の局所座標の位置;

use super::penetration_depth::符号付き貫通量メートル;

/// 接触点集合が持つ1点。2つの形それぞれの上の点と、符号付き貫通量と、特徴の識別を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触解法の候補点<特徴の識別> {
    第1の形の上の位置: 形の局所座標の位置,
    第2の形の上の位置: 形の局所座標の位置,
    貫通量: 符号付き貫通量メートル,
    特徴の識別: 特徴の識別,
}

impl<特徴の識別> 接触解法の候補点<特徴の識別> {
    pub(super) fn 生成する(
        第1の形の上の位置: 形の局所座標の位置,
        第2の形の上の位置: 形の局所座標の位置,
        貫通量: 符号付き貫通量メートル,
        特徴の識別: 特徴の識別,
    ) -> Self {
        Self {
            第1の形の上の位置,
            第2の形の上の位置,
            貫通量,
            特徴の識別,
        }
    }

    /// 第1の形の表面のうち、この候補点が指す点。
    pub fn 第1の形の上の位置(&self) -> 形の局所座標の位置 {
        self.第1の形の上の位置
    }

    /// 第2の形の表面のうち、この候補点が指す点。
    pub fn 第2の形の上の位置(&self) -> 形の局所座標の位置 {
        self.第2の形の上の位置
    }

    /// 2つの形がこの点で食い込んでいる符号付きの長さ。接しているだけなら0であり、負はその長さだけ離れていることを表す。
    pub fn 符号付き貫通量(&self) -> 符号付き貫通量メートル {
        self.貫通量
    }

    /// この候補点がどの特徴とどの特徴の間で生まれたか。次の刻みで同じ接触を見つけ直すための綴りである。
    pub fn 特徴の識別(&self) -> &特徴の識別 {
        &self.特徴の識別
    }

    /// この候補点が幾何の事実としての接触点であるか。符号付き貫通量が0以上、すなわち2つの形がこの点で
    /// 触れているか食い込んでいるときに真である。接触生成の余白の内側で離れている候補点では偽になる。
    pub fn 実際に触れているか(&self) -> bool {
        self.貫通量.値() >= 0.0
    }
}
