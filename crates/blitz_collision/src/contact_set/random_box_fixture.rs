//! 無作為な直方体を次々に作る生成元。分離軸の完全性と不変条件の反証が同じ散らし方を共有する。
//!
//! 擬似乱数を保持して自分のメソッドで進めるのは、乱数の並びを進める副作用が自由関数の連鎖を流れないように
//! するためである。動く形の索引の見本と、動く形の対の対称性の反証が同じ形を取っている。
//!
//! 中心の散らす幅と半分の長さの範囲は、2つの直方体が重なる場合と離れる場合がどちらも十分な数だけ出るように
//! 選んである。幅を広げると離れる対ばかりになり、狭めると重なる対ばかりになって、どちらの側の反証も薄くなる。
//!
//! 回転の軸が零に近い組では向きが定まらないため、天頂の軸を代わりに使う。四元数の生成が長さ零の軸を拒む
//! ことへの備えである。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use crate::pseudo_random_fixture::決まった種から進む擬似乱数;
use crate::shape::任意姿勢の直方体;

use super::query_fixture::{直方体を作る, 軸まわりの回転};

// 中心の成分が入る範囲であるメートル。
const 中心の範囲メートル: f32 = 1.5;
// 軸ごとの半分の長さが入る範囲であるメートル。
const 半分の長さの下限メートル: f32 = 0.2;
const 半分の長さの上限メートル: f32 = 1.2;
// 回転の軸として使える最小の成分の絶対値の和。
const 回転の軸として使える最小の大きさ: f32 = 0.05;

pub(super) struct 無作為の直方体の生成元 {
    乱数: 決まった種から進む擬似乱数,
}

impl 無作為の直方体の生成元 {
    pub(super) fn 種から始める(種: u64) -> Self {
        Self {
            乱数: 決まった種から進む擬似乱数::種から始める(種),
        }
    }

    pub(super) fn 次の直方体を作る(&mut self) -> 任意姿勢の直方体 {
        let 中心 = self.次の三成分を作る(-中心の範囲メートル, 中心の範囲メートル);
        let 軸 = self.次の三成分を作る(-1.0, 1.0);
        let 度 = self.乱数.単精度の範囲の中の値(0.0, 360.0);
        let 半分 = self.次の三成分を作る(半分の長さの下限メートル, 半分の長さの上限メートル);
        let 姿勢 = if 軸[0].abs() + 軸[1].abs() + 軸[2].abs() < 回転の軸として使える最小の大きさ {
            軸まわりの回転([0.0, 1.0, 0.0], 度)
        } else {
            軸まわりの回転(軸, 度)
        };
        直方体を作る(中心, 姿勢, 半分)
    }

    fn 次の三成分を作る(&mut self, 下限: f32, 上限: f32) -> [f32; 3] {
        [
            self.乱数.単精度の範囲の中の値(下限, 上限),
            self.乱数.単精度の範囲の中の値(下限, 上限),
            self.乱数.単精度の範囲の中の値(下限, 上限),
        ]
    }
}
