//! 2本の線分が最も近づく点の組を求める工程。辺の向きの外積が最小の貫通の軸であるときの、唯一の接触点を作る。
//!
//! 直方体どうしの辺の組と、直方体の辺と三角形の辺の組が同じ計算を使うため、形の種類に依らない入口をここに置く。
//! 受け取るのは2本の線分の始点と変位であり、返すのはそれぞれの線分の上の点である。
//!
//! 比が範囲を外れたときに端へ寄せるのは、分離軸が2つの辺の向きの外積であるとき最近接点が数学的にはどちらの
//! 線分の中にも在り、外れるとすれば丸めによるものだからである。捨てると、重なっている2つの形の接触点が
//! 1つも出ない。寄せ方の説明は `crates/blitz_collision/src/solver/line_pair.rs` にある。
//!
//! 2本が平行で最近接点が1組に定まらないときは、どちらも始点を返す。平行な2辺の外積は零であり、分離軸の走査が
//! その軸を飛ばすため、この落とし先は到達しない枝である。

use crate::shape::{形の局所座標の位置, 形の局所座標の変位};
use crate::solver::二つの直線の最近接の媒介変数;

pub(super) struct 二つの線分の最近接の点 {
    第1の線分の上の点: 形の局所座標の位置,
    第2の線分の上の点: 形の局所座標の位置,
}

impl 二つの線分の最近接の点 {
    pub(super) fn 二本の線分から求める(
        第1の始点: 形の局所座標の位置,
        第1の変位: 形の局所座標の変位,
        第2の始点: 形の局所座標の位置,
        第2の変位: 形の局所座標の変位,
    ) -> Self {
        let Some(比の組) = 二つの直線の最近接の媒介変数::範囲へ寄せた組を求める(
            第1の変位,
            第2の変位,
            第2の始点.終点までの変位を求める(第1の始点),
        ) else {
            return Self {
                第1の線分の上の点: 第1の始点,
                第2の線分の上の点: 第2の始点,
            };
        };
        Self {
            第1の線分の上の点: 第1の始点.検査済みの変位だけ進んだ位置を求める(第1の変位.実数倍する(比の組.第1の直線の比())),
            第2の線分の上の点: 第2の始点.検査済みの変位だけ進んだ位置を求める(第2の変位.実数倍する(比の組.第2の直線の比())),
        }
    }

    pub(super) fn 第1の線分の上の点(&self) -> 形の局所座標の位置 {
        self.第1の線分の上の点
    }

    pub(super) fn 第2の線分の上の点(&self) -> 形の局所座標の位置 {
        self.第2の線分の上の点
    }
}
