//! 参照の面の枠: 切り抜きの基準になる面そのものと、その面を囲む側の平面をまとめたものである。入射面の輪郭を
//! この枠へ通すと、参照面の内側に収まる接触点の候補が出る。
//!
//! 面と側の平面を1つの型にまとめるのは、側の平面がどの面を囲むものかを別々に持ち回すと取り違えられるためで
//! ある。参照面が直方体の面なら側の平面は4つ、三角形なら3つであり、どちらも同じ切り抜きの手順を通る。
//!
//! 面の外向きの単位法線は入射面の側を向く。貫通量はこの向きへ測った隔たりの符号を反転した量であり、
//! 参照面の平面より内側に在る点で0以上になる。
//!
//! 切り抜きの手順は側の平面を並びの順に1つずつ通すものであり、1つ通すごとに頂点が高々1つ増える。順序を
//! 変えても数学的な結果は同じであるが、丸めの入り方が変わるため並びを固定する。

use crate::shape::{形の局所座標の位置, 形の局所座標の変位};

use super::clip_plane::参照面の側の平面;
use super::clip_polygon::切り抜き中の多角形;
use super::clip_reference_feature::参照面の辺で切り取った点の特徴の綴り;
use super::error::接触点集合の問い合わせエラー;
use super::generation_margin::接触生成の余白メートル;
use super::penetration_depth::符号付き貫通量メートル;

// 参照面を囲む側の平面の最大の数。直方体の面が4つ、三角形が3つである。
const 側の平面の最大の数: usize = 4;

pub(super) struct 参照の面の枠<参照側の特徴: 参照面の辺で切り取った点の特徴の綴り> {
    面の基準点: 形の局所座標の位置,
    面の外向きの単位法線: 形の局所座標の変位,
    面そのものの特徴: 参照側の特徴,
    側の平面: [Option<参照面の側の平面<参照側の特徴>>; 側の平面の最大の数],
    側の平面の件数: usize,
}

impl<参照側の特徴: 参照面の辺で切り取った点の特徴の綴り> 参照の面の枠<参照側の特徴> {
    pub(super) fn 生成する(
        面の基準点: 形の局所座標の位置,
        面の外向きの単位法線: 形の局所座標の変位,
        面そのものの特徴: 参照側の特徴,
        側の平面: [Option<参照面の側の平面<参照側の特徴>>; 側の平面の最大の数],
        側の平面の件数: usize,
    ) -> Self {
        Self {
            面の基準点,
            面の外向きの単位法線,
            面そのものの特徴,
            側の平面,
            側の平面の件数,
        }
    }

    pub(super) fn 面そのものの特徴(&self) -> 参照側の特徴 {
        self.面そのものの特徴
    }

    // 入射面の輪郭を側の平面で順に切り詰める。
    pub(super) fn 入射の多角形を切り抜く<入射側の特徴: Copy>(
        &self,
        入射の多角形: 切り抜き中の多角形<参照側の特徴, 入射側の特徴>,
        入射面そのものの特徴: 入射側の特徴,
    ) -> Result<切り抜き中の多角形<参照側の特徴, 入射側の特徴>, 接触点集合の問い合わせエラー> {
        let mut 多角形 = 入射の多角形;
        for 平面 in self.側の平面[..self.側の平面の件数].iter().flatten() {
            多角形 = 平面.この平面で多角形を切り抜く(&多角形, 入射面そのものの特徴)?;
        }
        Ok(多角形)
    }

    // 切り抜いた点1つが参照面の平面へどれだけ食い込んでいるか。接触生成の余白より外へ出た点は接触点にしないため
    // 値なしを返し、余白の内側で離れている点は負の符号付き貫通量として返す。
    pub(super) fn 点の符号付き貫通量を求める(
        &self,
        点: 形の局所座標の位置,
        余白: 接触生成の余白メートル,
    ) -> Option<符号付き貫通量メートル> {
        let 外向きの隔たり = self.面の基準点.終点までの変位を求める(点).内積(self.面の外向きの単位法線);
        符号付き貫通量メートル::余白の内側であることを確かめて生成する(-外向きの隔たり, 余白).ok()
    }

    // 入射面の上の点から、参照面の平面の上の点へ戻す。外向きの単位法線の向きへ符号付き貫通量だけ進めた点である。
    // 離れている点では負の長さだけ進むため、参照面の平面より入射面の側へ戻る。
    pub(super) fn 参照面の上の点を求める(
        &self,
        入射面の上の点: 形の局所座標の位置,
        貫通量: 符号付き貫通量メートル,
    ) -> Result<形の局所座標の位置, 接触点集合の問い合わせエラー> {
        Ok(入射面の上の点.変位だけ進んだ位置を求める(self.面の外向きの単位法線.実数倍する(貫通量.値()))?)
    }
}
