//! 1本の軸へ形を射影した区間と、2つの区間を比べて得る重なりの深さと押す向き。
//!
//! 区間と重なりを同じところへ置くのは、重なりが2つの区間の間にだけ定義される量であり、区間の型を知らずに
//! 読める値ではないためである。切り離すと、どちらの区間が第1の形のものかを呼び出し側が覚えることになる。
//!
//! 射影の基準点は第1の形の中心である。区間そのものの値は基準点の取り方で動くが、重なりは2つの区間の差
//! だけで決まるため基準点に依らない。第1の形の中心を基準にするのは、原点から遠い場所で射影の値が大きく
//! 育ち、その差を取る減算で桁が落ちることを防ぐためである。
//!
//! 押す向きは、第2の形をどちらへ動かせば少ない移動で離れるかで決める。正の側へ押す量と負の側へ押す量の
//! 小さいほうが重なりの深さであり、負の側が選ばれたときに軸の向きを反転する。2つの量が等しいときは
//! 反転しない。答えを入力だけで決めるためである。

/// 1本の軸へ形を射影した区間。値は第1の形の中心を基準にしたメートルである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 軸への射影の区間 {
    最小: f64,
    最大: f64,
}

impl 軸への射影の区間 {
    // 中心の射影と、そこから両側へ伸びる広がりから組む。任意姿勢の直方体の射影がこの形になる。
    pub(super) fn 中心と広がりから組む(中心の射影: f64, 広がり: f64) -> Self {
        Self {
            最小: 中心の射影 - 広がり,
            最大: 中心の射影 + 広がり,
        }
    }

    // 頂点の射影の並びから、最小と最大を選んで組む。三角形の射影がこの形になる。
    pub(super) fn 頂点の射影から組む(頂点の射影: [f64; 3]) -> Self {
        Self {
            最小: 頂点の射影.into_iter().fold(f64::INFINITY, f64::min),
            最大: 頂点の射影.into_iter().fold(f64::NEG_INFINITY, f64::max),
        }
    }

    // この区間を第1の形、相手を第2の形として比べた重なり。
    pub(super) fn 相手との重なりを求める(&self, 相手: &Self) -> 軸1本での重なり {
        let 正の側へ押す量 = self.最大 - 相手.最小;
        let 負の側へ押す量 = 相手.最大 - self.最小;
        軸1本での重なり {
            重なりの深さ: 正の側へ押す量.min(負の側へ押す量),
            軸の向きを反転するか: 負の側へ押す量 < 正の側へ押す量,
        }
    }
}

/// 1本の軸で2つの形を比べた結果。深さが負なら、その軸が2つの形を分離している。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 軸1本での重なり {
    重なりの深さ: f64,
    軸の向きを反転するか: bool,
}

impl 軸1本での重なり {
    pub(super) fn 重なりの深さ(&self) -> f64 {
        self.重なりの深さ
    }

    pub(super) fn 軸の向きを反転するか(&self) -> bool {
        self.軸の向きを反転するか
    }

    // 接しているだけの状態(深さがちょうど0)は重なりの側に数える。重なっているか接している2つの形の接触点を
    // 求めるのがこの問いだからである。深さが数でない値になる入力(有限でない座標)は形の生成が拒んでいるが、
    // ここでも分離の側へ倒し、判定の外へ数でない値を持ち出さない。
    pub(super) fn 二つの形を分離しているか(&self) -> bool {
        self.重なりの深さ.is_nan() || self.重なりの深さ < 0.0
    }
}
