//! 符号付き貫通量メートル: 接触点1つで、2つの形が共有の単位法線に沿ってどれだけ食い込んでいるかの符号付きの
//! 長さである。正は食い込み、0は接しているだけ、負はその長さだけ離れていることを表す。
//!
//! 裸の実数で持たないのは、この量が接触生成の余白の内側にあること(負の側が余白の長さまでで止まること)を
//! 型が保証するためである。余白より外へ出た点は接触点にしない。落とす工程がこの型の入口に乗っている。
//!
//! 負の値を許すのは、面で乗った2つの直方体の角が離れる向きへわずかに揺れても接触点の数と特徴の識別を保つ
//! ためである。理由は `crates/blitz_collision/src/contact_set/generation_margin.rs` にある。
//!
//! 単位法線と組にして初めて意味を持つ。2つの形の上の点の隔たりを、その法線に沿って測った長さだからである。

use super::error::接触点集合の問い合わせエラー;
use super::generation_margin::接触生成の余白メートル;

/// 接触点1つで2つの形が食い込んでいる符号付きの長さ。負はその長さだけ離れていることを表す。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 符号付き貫通量メートル {
    値: f64,
}

impl 符号付き貫通量メートル {
    /// 有限であり、負の側が接触生成の余白の内側であることを確かめて作る。余白より外と有限でない値は型付きエラーで拒む。
    pub fn 余白の内側であることを確かめて生成する(
        値: f64,
        余白: 接触生成の余白メートル,
    ) -> Result<Self, 接触点集合の問い合わせエラー> {
        if !値.is_finite() || !余白.余白の内側の符号付き貫通量か(値) {
            return Err(接触点集合の問い合わせエラー::貫通量が余白より外であるか有限でない);
        }
        Ok(Self { 値 })
    }

    /// 食い込んでいる符号付きの長さであるメートル。
    pub fn 値(&self) -> f64 {
        self.値
    }
}
