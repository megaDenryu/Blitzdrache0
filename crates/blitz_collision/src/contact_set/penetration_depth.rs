//! 貫通量メートル: 接触点1つで、2つの形がどれだけ食い込んでいるかの長さである。
//!
//! 裸の実数で持たないのは、この量が符号を持たないこと(負の値は「離れている」であって貫通ではないこと)を
//! 型が保証するためである。0は接しているだけの状態を表し、値として許す。重なっている形の接触点集合を
//! 求める問いでは、接しているだけの点も接触点である。
//!
//! 単位法線と組にして初めて意味を持つ。2つの形の上の点の隔たりを、その法線に沿って測った長さだからである。

use super::error::接触点集合の問い合わせエラー;

/// 接触点1つで2つの形が食い込んでいる長さ。0以上の有限のメートルである。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 貫通量メートル {
    値: f64,
}

impl 貫通量メートル {
    /// 0以上の有限値であることを確かめて作る。負の値と有限でない値は型付きエラーで拒む。
    pub fn 生成する(値: f64) -> Result<Self, 接触点集合の問い合わせエラー> {
        if !値.is_finite() || 値 < 0.0 {
            return Err(接触点集合の問い合わせエラー::貫通量が負であるか有限でない);
        }
        Ok(Self { 値 })
    }

    /// 食い込んでいる長さであるメートル。
    pub fn 値(&self) -> f64 {
        self.値
    }
}
