//! 辺の向きの外積が最小の貫通の軸になる場面と、分離している場面と、切り抜きの点数が上限を越えないことの反証。
//!
//! 辺どうしの交差は、面での接触と違って接触点が1つしか出ない。1つしか出ないことがこの群の要点であり、
//! 面の軸を優先する決まり(外積の軸は自分の誤差の上界だけ小さくなければ入れ替えない)が働いてもなお、
//! 明らかに浅い外積の軸は選ばれることを見る。

#![allow(clippy::unwrap_used)]

use super::generation_margin::接触生成の余白メートル;
use crate::contact_set::box_pair_query::{二つの直方体の重なりの接触点集合, 直方体どうしの接触点集合の問い合わせ};
use crate::contact_set::manifold_capacity::接触点の上限;
use crate::oriented_box::直方体で当たった特徴;

use super::box_pair_answer_fixture::床を作る;
use super::query_fixture::{位置の成分, 回転なし, 直方体を作る, 軸まわりの回転};

#[test]
fn 直角に交わる2本の辺は1つの接触点を作る() {
    let 上へ尖った箱 = 直方体を作る([0.0, 0.0, 0.0], 軸まわりの回転([0.0, 0.0, 1.0], 45.0), [1.0, 1.0, 1.0]);
    let 沈み = 0.1_f32;
    let 下へ尖った箱 = 直方体を作る(
        [0.0, 2.0 * (2.0_f32).sqrt() - 沈み, 0.0],
        軸まわりの回転([1.0, 0.0, 0.0], 45.0),
        [1.0, 1.0, 1.0],
    );
    let 問い合わせ = 直方体どうしの接触点集合の問い合わせ::二つの直方体と余白から生成する(
        &上へ尖った箱,
        &下へ尖った箱,
        接触生成の余白メートル::余白を持たない(),
    );
    let 二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) = 問い合わせ.二つの直方体の重なりの接触点集合を求める().unwrap()
    else {
        panic!("交わっている2本の辺が離れていると答えた");
    };
    assert_eq!(集合.件数(), 1, "辺どうしの交差の接触点が1つでない");
    let 点 = 集合.接触解法の候補点を順に並べる().next().unwrap();
    assert!(
        (点.符号付き貫通量().値() - f64::from(沈み)).abs() < 1e-5,
        "辺どうしの交差の貫通量が沈みから離れている(実測{})",
        点.符号付き貫通量().値()
    );
    let 第1の側 = 位置の成分(点.第1の形の上の位置());
    assert!(
        第1の側[0].abs() < 1e-6 && (第1の側[1] - (2.0_f64).sqrt()).abs() < 1e-5,
        "第1の直方体の上の接触点が上の辺に乗っていない"
    );
    assert!(
        matches!(点.特徴の識別().第1の直方体の特徴(), 直方体で当たった特徴::直方体の辺(_)),
        "第1の直方体の特徴が辺でない"
    );
    assert!(
        matches!(点.特徴の識別().第2の直方体の特徴(), 直方体で当たった特徴::直方体の辺(_)),
        "第2の直方体の特徴が辺でない"
    );
}

#[test]
fn 離れた2つの直方体は離れていると答える() {
    let 床 = 床を作る();
    let 箱 = 直方体を作る([0.0, 5.0, 0.0], 回転なし(), [1.0, 1.0, 1.0]);
    let 問い合わせ = 直方体どうしの接触点集合の問い合わせ::二つの直方体と余白から生成する(
        &箱,
        &床,
        接触生成の余白メートル::余白を持たない(),
    );
    assert_eq!(
        問い合わせ.二つの直方体の重なりの接触点集合を求める().unwrap(),
        二つの直方体の重なりの接触点集合::二つの直方体は離れている,
        "明らかに離れた2つの直方体が重なっていると答えた"
    );
}

#[test]
fn 接しているだけの2つの直方体は重なっている側で答える() {
    let 床 = 床を作る();
    let 箱 = 直方体を作る([0.0, 1.0, 0.0], 回転なし(), [1.0, 1.0, 1.0]);
    let 問い合わせ = 直方体どうしの接触点集合の問い合わせ::二つの直方体と余白から生成する(
        &箱,
        &床,
        接触生成の余白メートル::余白を持たない(),
    );
    let 二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) = 問い合わせ.二つの直方体の重なりの接触点集合を求める().unwrap()
    else {
        panic!("接しているだけの2つの直方体が離れていると答えた");
    };
    assert_eq!(集合.件数(), 4, "接しているだけの直方体の接触点が4つでない");
    for 点 in 集合.接触解法の候補点を順に並べる() {
        assert!(点.符号付き貫通量().値() < 1e-9, "接しているだけの直方体の貫通量が0でない");
    }
}

#[test]
fn 面どうしがずれて重なっても接触点は上限を越えない() {
    // 参照面と入射面が45度ずれた姿勢では、切り抜きの結果が8角形になる。上限の導出の等号が立つ場面である。
    let 床 = 直方体を作る([0.0, -1.0, 0.0], 回転なし(), [1.0, 1.0, 1.0]);
    let 箱 = 直方体を作る([0.0, 0.9, 0.0], 軸まわりの回転([0.0, 1.0, 0.0], 45.0), [1.0, 1.0, 1.0]);
    let 問い合わせ = 直方体どうしの接触点集合の問い合わせ::二つの直方体と余白から生成する(
        &箱,
        &床,
        接触生成の余白メートル::余白を持たない(),
    );
    let 二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) = 問い合わせ.二つの直方体の重なりの接触点集合を求める().unwrap()
    else {
        panic!("重なっているはずの直方体が離れていると答えた");
    };
    assert_eq!(集合.件数(), 接触点の上限, "45度ずれた面どうしの接触点が上限に等しくない");
    for 点 in 集合.接触解法の候補点を順に並べる() {
        assert!(
            (点.符号付き貫通量().値() - 0.1).abs() < 1e-6,
            "45度ずれた面どうしの貫通量が0.1から離れている"
        );
    }
}
