//! 接触点を上限つきの受け皿へ積む器。切り抜きの結果と辺どうしの1点のどちらもここを通って接触点集合になる。
//!
//! 集合そのものと別の型にするのは、積んでいる途中の状態(まだ単位法線が決まっていない受け皿)を完成した集合の
//! 型が持たないためである。完成した集合は法線を必ず持ち、件数が上限を越えていないことも決まっている。
//!
//! 上限を越えた積み込みを型付きエラーで返すのは、切り抜きの点数の上界の導出が破れたことを意味するためである。
//! 上界は凸性を前提にしており、丸めで凸でなくなった多角形では破れうる。落とさずに黙って捨てると、重なって
//! いるのに接触点の足りない集合が出て、剛体の側で物体が沈む形で初めて見つかることになる。

use blitz_math::{ローカル, 方向};

use super::error::接触点集合の問い合わせエラー;
use super::manifold::接触点集合;
use super::manifold_capacity::接触点の上限;
use super::solver_candidate_point::接触解法の候補点;

pub(super) struct 接触点を積む器<特徴の識別: Copy> {
    接触点: [Option<接触解法の候補点<特徴の識別>>; 接触点の上限],
    件数: usize,
}

impl<特徴の識別: Copy> 接触点を積む器<特徴の識別> {
    pub(super) fn 空から始める() -> Self {
        Self {
            接触点: [None; 接触点の上限],
            件数: 0,
        }
    }

    pub(super) fn 接触解法の候補点を1つ積む(
        &mut self,
        点: 接触解法の候補点<特徴の識別>,
    ) -> Result<(), 接触点集合の問い合わせエラー> {
        let Some(置き場) = self.接触点.get_mut(self.件数) else {
            return Err(接触点集合の問い合わせエラー::受け皿の上限を越えた { 上限: 接触点の上限 });
        };
        *置き場 = Some(点);
        self.件数 += 1;
        Ok(())
    }

    pub(super) fn 共有の単位法線を添えて集合にする(
        self, 共有の単位法線: 方向<ローカル>
    ) -> 接触点集合<特徴の識別> {
        接触点集合::生成する(共有の単位法線, self.接触点, self.件数)
    }
}
