//! 接触点1つが必ず満たす条件の反証。貫通量が0以上であることと、2つの形の上の点が共有の単位法線で
//! つながっていることを、無作為に散らした対で確かめる。
//!
//! 完全性の反証と別のファイルへ置くのは、こちらが「重なっていると答えた後に返した中身」を見るためである。
//! 完全性の反証は重なっているかどうかの1ビットしか見ない。
//!
//! つながりの条件は、第2の形の上の点が第1の形の上の点から共有の単位法線の向きへ貫通量だけ戻った点である
//! ことである。許容の幅を単精度の刻みの側に取るのは、共有の単位法線が単精度へ狭められて返るためであり、
//! 位置と貫通量そのものは倍精度のまま返る。

#![allow(clippy::unwrap_used)]

use super::cross_axis_preference::外積の軸へ切り替える優位幅メートル;
use super::generation_margin::接触生成の余白メートル;
use crate::contact_set::box_pair_query::{二つの直方体の重なりの接触点集合, 直方体どうしの接触点集合の問い合わせ};
use crate::shape::形の局所座標の位置;

use super::random_box_fixture::無作為の直方体の生成元;

// 共有の単位法線が単精度へ狭められることから来る、つながりの条件の許容の幅であるメートル。
const つながりの許容メートル: f64 = 1.0e-5;

fn 位置の成分(位置: 形の局所座標の位置) -> [f64; 3] {
    [位置.xのメートル(), 位置.yのメートル(), 位置.zのメートル()]
}

#[test]
fn 無作為に散らした対の接触点は貫通量が0以上で2つの点が共有の法線でつながる() {
    let mut 生成元 = 無作為の直方体の生成元::種から始める(0x5eed_1234_abcd_0002);
    let mut 調べた接触点の件数 = 0;
    for 番号 in 0..1000 {
        let (第1, 第2) = (生成元.次の直方体を作る(), 生成元.次の直方体を作る());
        let 問い合わせ = 余白も優位幅も持たない直方体どうしの問い合わせを組む(&第1, &第2);
        let 二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) = 問い合わせ.二つの直方体の重なりの接触点集合を求める().unwrap()
        else {
            continue;
        };
        let 法線 = 集合.共有の単位法線();
        let 単位法線 = [f64::from(法線.x()), f64::from(法線.y()), f64::from(法線.z())];
        for 点 in 集合.接触解法の候補点を順に並べる() {
            assert!(点.符号付き貫通量().値() >= 0.0, "{番号}番目の対の接触点の貫通量が負である");
            let 第1の側 = 位置の成分(点.第1の形の上の位置());
            let 第2の側 = 位置の成分(点.第2の形の上の位置());
            for 成分 in 0usize..3 {
                let 期待 = 第1の側[成分] - 点.符号付き貫通量().値() * 単位法線[成分];
                assert!(
                    (第2の側[成分] - 期待).abs() < つながりの許容メートル,
                    "{番号}番目の対の接触点で2つの点が共有の法線でつながっていない"
                );
            }
            調べた接触点の件数 += 1;
        }
    }
    assert!(
        調べた接触点の件数 > 300,
        "接触点が少なすぎて不変条件を試せていない(実測{調べた接触点の件数}件)"
    );
}
