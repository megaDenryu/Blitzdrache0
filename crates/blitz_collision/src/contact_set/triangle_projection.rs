//! 三角形を1本の軸へ射影する工程。受け取るのは基準点と軸の向き、返すのはその軸の上の区間である。
//!
//! 直方体の射影と別のファイルへ置くのは、区間の作り方が違うためである。直方体は中心について対称であるから
//! 中心の射影と広がりで区間を組めるが、三角形は対称でないため3つの頂点の射影の最小と最大をそのまま取る。
//!
//! 厚みは持たない。三角形は面積を持つが体積を持たない形であり、面の法線の向きへ射影した区間は1点へつぶれる。
//! そのつぶれた区間が直方体の区間と重なるかどうかが、面の法線を分離軸として調べることの意味である。

use crate::shape::{三角形の頂点の番号, 形の局所座標の位置, 形の局所座標の変位, 面の向きを備えた三角形};

use super::axis_interval::軸への射影の区間;

impl 面の向きを備えた三角形 {
    // 基準点から見て、この三角形が軸の向きの上で占める区間。
    pub(super) fn 基準点から見た軸への射影の区間を求める(
        &self,
        基準点: 形の局所座標の位置,
        軸の向き: 形の局所座標の変位,
    ) -> 軸への射影の区間 {
        軸への射影の区間::頂点の射影から組む(
            三角形の頂点の番号::並べる().map(|番号| 基準点.終点までの変位を求める(self.頂点の位置(番号)).内積(軸の向き)),
        )
    }

    // 基準点から3つの頂点までの隔たりのうち最も大きいもの。分離軸の重なりの誤差の上界が使う尺度の一部である。
    // 隔たりの二乗の平方根を取らずに成分の絶対値の最大の3倍で上から抑えるのは、尺度が上界であればよく、
    // 平方根を通す必要がないためである。
    pub(super) fn 基準点から最も遠い頂点までの隔たりの上界のメートル(&self, 基準点: 形の局所座標の位置) -> f64 {
        三角形の頂点の番号::並べる()
            .into_iter()
            .map(|番号| 基準点.終点までの変位を求める(self.頂点の位置(番号)).成分の絶対値の和のメートル())
            .fold(0.0_f64, f64::max)
    }
}
