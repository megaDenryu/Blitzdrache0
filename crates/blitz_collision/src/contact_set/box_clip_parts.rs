//! 直方体の1つの面から、切り抜きの部品(参照の面の枠と入射の多角形)を組む工程。
//!
//! 参照の枠と入射の多角形を同じところへ置くのは、どちらも「直方体の面1つを切り抜きの言葉へ写す」という
//! 1つの工程であり、面の輪郭の頂点の並びと側の平面の並びが同じ4つの辺を別の役で見たものだからである。
//! 切り離すと、輪郭の順と側の平面の順が食い違っても気づけない。
//!
//! 参照の枠の側の平面は、参照面に隣り合う4つの面である。その平面の内向きの法線は隣の面の外向きの単位法線を
//! 反転したものであり、切り取る辺は参照面と隣の面が共有する辺である。切り取られた接触点の参照側の特徴が
//! その辺になる。
//!
//! 入射の多角形の頂点は面の輪郭の順であり、頂点の特徴はその頂点、辺の特徴は輪郭で隣り合う2つの頂点が
//! 共有する辺である。輪郭の隣り合う2つの頂点は、面に垂直な軸以外の2軸のうち片方の側だけが違うため、
//! 共有する辺はその違う軸に沿って伸びる。

use crate::oriented_box::{直方体で当たった特徴, 直方体の面, 直方体の頂点};
use crate::shape::{任意姿勢の直方体の倍精度の幾何, 直方体の面の向き, 直方体自身の座標軸};

use super::box_feature_support::{二つの面が共有する辺を組む, 沿う軸と軸ごとの側から辺を組む};
use super::clip_feature_pair::切り抜きの特徴の対;
use super::clip_plane::参照面の側の平面;
use super::clip_polygon::{切り抜き中の多角形, 多角形の頂点};
use super::error::接触点集合の問い合わせエラー;
use super::reference_frame::参照の面の枠;

impl 任意姿勢の直方体の倍精度の幾何 {
    // 面1つを参照の面の枠へ写す。側の平面は、その面に隣り合う4つの面から作る。
    // 注意: 内側の2重の繰り返しは軸2本と側2つでちょうど4回であり、側の平面の受け皿の長さと一致する。
    // 受け皿を短くすると添字が範囲を出る。
    pub(super) fn 面から参照の枠を組む(&self, 面: 直方体の面) -> 参照の面の枠<直方体で当たった特徴> {
        let mut 側の平面 = [None; 4];
        let mut 件数 = 0;
        for 隣の軸 in [面.軸().次の軸(), 面.軸().次の軸().次の軸()] {
            for 隣の側 in 直方体の面の向き::並べる() {
                let 隣の面 = 直方体の面::生成する(隣の軸, 隣の側);
                let Some(共有する辺) = 二つの面が共有する辺を組む(面, 隣の面) else {
                    continue;
                };
                側の平面[件数] = Some(参照面の側の平面::生成する(
                    self.面の中央の位置を求める(隣の面),
                    self.面の外向きの単位向きを求める(隣の面).実数倍する(-1.0),
                    直方体で当たった特徴::直方体の辺(共有する辺),
                ));
                件数 += 1;
            }
        }
        参照の面の枠::生成する(
            self.面の中央の位置を求める(面),
            self.面の外向きの単位向きを求める(面),
            直方体で当たった特徴::直方体の面(面),
            側の平面,
            件数,
        )
    }

    // 面1つを入射の多角形へ写す。参照側の特徴には、まだ切り取られていないことを表す参照面そのものを入れる。
    pub(super) fn 面から入射の多角形を組む<参照側の特徴: Copy>(
        &self,
        面: 直方体の面,
        参照面そのものの特徴: 参照側の特徴,
    ) -> Result<切り抜き中の多角形<参照側の特徴, 直方体で当たった特徴>, 接触点集合の問い合わせエラー> {
        let 輪郭 = self.面の輪郭の頂点を並べる(面);
        let mut 多角形 = 切り抜き中の多角形::空から始める();
        for 番号 in 0..輪郭.len() {
            let (この頂点, 次の頂点) = (輪郭[番号], 輪郭[(番号 + 1) % 輪郭.len()]);
            let 共有する辺 = 沿う軸と軸ごとの側から辺を組む(
                輪郭で隣り合う2つの頂点が共有する辺の沿う軸を求める(この頂点, 次の頂点),
                直方体自身の座標軸::並べる().map(|軸| この頂点.軸ごとの側(軸)),
            );
            多角形.頂点を1つ積む(多角形の頂点::生成する(
                self.頂点の位置を求める(この頂点),
                切り抜きの特徴の対::生成する(参照面そのものの特徴, 直方体で当たった特徴::直方体の頂点(この頂点)),
                切り抜きの特徴の対::生成する(参照面そのものの特徴, 直方体で当たった特徴::直方体の辺(共有する辺)),
            ))?;
        }
        Ok(多角形)
    }
}

// 輪郭で隣り合う2つの頂点が共有する辺の沿う軸。2つの頂点は1本の軸についてだけ側が違うため、その軸に沿って
// 辺が伸びる。並びの決まりから必ず1本見つかるが、見つからない入力に備えて並びの先頭の軸へ落とす。
fn 輪郭で隣り合う2つの頂点が共有する辺の沿う軸を求める(
    この頂点: 直方体の頂点,
    次の頂点: 直方体の頂点,
) -> 直方体自身の座標軸 {
    直方体自身の座標軸::並べる()
        .into_iter()
        .find(|軸| この頂点.軸ごとの側(*軸) != 次の頂点.軸ごとの側(*軸))
        .unwrap_or(直方体自身の座標軸::X軸)
}
