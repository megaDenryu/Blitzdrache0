//! 直方体と三角形の13本の分離軸を1本ずつ調べ、離れているかどうかと、重なっているなら最小の貫通の軸を求める工程。
//!
//! 直方体どうしの走査と別のファイルへ置くのは、調べる軸の目録も、片側の形の射影の作り方も違うためである。
//! 射影の基準点を直方体の中心に取る理由と、軸の向きを長さ1に正してから深さを比べる理由は同じである。
//!
//! 参照軸の選択には解法向けの方針が1つ入る。幾何が決めた最小の軸が2つの辺の向きの外積の軸であっても、その優位
//! (面の軸の深さから外積の軸の深さを引いた長さ)が「倍精度の丸めの上界 + 外積の軸へ切り替える優位幅」を超えない
//! 限り、参照軸を面の軸のままにする。**幾何の最小がどちらかは決まっている。** 決まっている事実を曖昧にするのでは
//! なく、接触解法へ渡す参照面をどちらにするかだけをこの方針が決める。面の軸どうしの比較は厳密のままである。
//! 理由と優位幅の意味は `crates/blitz_collision/src/contact_set/cross_axis_preference.rs` にある。
//!
//! 三角形の3辺の向きは、生成のときに長さ1へ正して保持する。外積の軸の誤差の上界の導出が、外積を作る2つの
//! 向きがどちらも長さ1であることを前提にしているためである。面積が零の三角形はこの形を作れないため、
//! どの辺も長さが零にならない。

use crate::shape::{
    三角形の頂点の番号, 任意姿勢の直方体の倍精度の幾何, 形の局所座標の位置, 形の局所座標の変位, 面の向きを備えた三角形
};

use super::box_triangle_axis::直方体と三角形の分離軸;
use super::cross_axis_margin::外積の軸の重なりの誤差の上界を求める;
use super::cross_axis_preference::外積の軸へ切り替える優位幅メートル;
use super::deepest_axis::{最も浅い重なりの軸だけを覚える器, 最小の貫通の軸};

pub(super) struct 直方体と三角形の分離軸の走査<'形の寿命> {
    直方体の幾何: &'形の寿命 任意姿勢の直方体の倍精度の幾何,
    三角形: &'形の寿命 面の向きを備えた三角形,
    辺の単位向き: [形の局所座標の変位; 3],
    外積の軸へ切り替える優位幅: 外積の軸へ切り替える優位幅メートル,
    誤差の上界の尺度のメートル: f64,
}

impl<'形の寿命> 直方体と三角形の分離軸の走査<'形の寿命> {
    // 三角形の辺の向きを長さ1に正せなければ値なしを返す。面の向きを備えた三角形は面積が零でないため、
    // この値なしは到達しない枝であるが、正す工程が値なしを返しうる以上ここで型として受け止める。
    pub(super) fn 生成する(
        直方体の幾何: &'形の寿命 任意姿勢の直方体の倍精度の幾何,
        三角形: &'形の寿命 面の向きを備えた三角形,
        外積の軸へ切り替える優位幅: 外積の軸へ切り替える優位幅メートル,
    ) -> Option<Self> {
        let mut 辺の単位向き = [形の局所座標の変位::零(); 3];
        for 番号 in 三角形の頂点の番号::並べる() {
            辺の単位向き[番号.並びの位置()] = 三角形.辺の変位を求める(番号).長さで正した変位を求める()?;
        }
        let 尺度 = 直方体の幾何.半分の長さの総和のメートル()
            + 三角形.基準点から最も遠い頂点までの隔たりの上界のメートル(直方体の幾何.中心());
        Some(Self {
            直方体の幾何,
            三角形,
            辺の単位向き,
            外積の軸へ切り替える優位幅,
            誤差の上界の尺度のメートル: 尺度,
        })
    }

    // 13本すべてで重なりが負でなければ最小の貫通の軸を返す。1本でも分離していれば値なしを返す。
    pub(super) fn 最も浅い重なりの軸を求める(&self) -> Option<最小の貫通の軸<直方体と三角形の分離軸>> {
        let mut 器 = 最も浅い重なりの軸だけを覚える器::まだ何も無い状態から始める();
        for 軸 in 直方体と三角形の分離軸::並べる() {
            let 向き = self.軸の向きを求める(軸);
            let 長さ = 向き.長さの二乗().sqrt();
            if 長さ.is_nan() || 長さ <= 0.0 {
                continue;
            }
            let 重なり = self
                .直方体の幾何
                .基準点から見た軸への射影の区間を求める(self.基準点(), 向き)
                .相手との重なりを求める(&self.三角形.基準点から見た軸への射影の区間を求める(self.基準点(), 向き));
            if 重なり.二つの形を分離しているか() {
                return None;
            }
            let 符号 = if 重なり.軸の向きを反転するか() { -1.0 } else { 1.0 };
            self.重なりを1本ぶん器へ数える(&mut 器, 軸, 重なり.重なりの深さ() / 長さ, 向き.実数倍する(符号 / 長さ), 長さ);
        }
        器.覚えている軸を取り出す()
    }

    // 1本の軸の深さを器へ渡す。面の軸は厳密な比較で、外積の軸は丸めの上界と解法向けの優位幅のぶんだけ厳しくして入れ替える。
    fn 重なりを1本ぶん器へ数える(
        &self,
        器: &mut 最も浅い重なりの軸だけを覚える器<直方体と三角形の分離軸>,
        軸: 直方体と三角形の分離軸,
        深さ: f64,
        正した向き: 形の局所座標の変位,
        外積の長さ: f64,
    ) {
        match 軸 {
            直方体と三角形の分離軸::直方体の面の軸(_) | 直方体と三角形の分離軸::三角形の面の法線 => {
                器.面の軸を1本数える(軸, 深さ, 正した向き);
            }
            直方体と三角形の分離軸::直方体の軸と三角形の辺の外積の軸 { .. } => 器.外積の軸を1本数える(
                軸,
                深さ,
                正した向き,
                self.外積の軸へ切り替える優位幅.丸めの上界へ足して外積の軸へ切り替える余地を求める(
                    外積の軸の重なりの誤差の上界を求める(self.誤差の上界の尺度のメートル, 外積の長さ),
                ),
            ),
        }
    }

    fn 基準点(&self) -> 形の局所座標の位置 {
        self.直方体の幾何.中心()
    }

    fn 軸の向きを求める(&self, 軸: 直方体と三角形の分離軸) -> 形の局所座標の変位 {
        match 軸 {
            直方体と三角形の分離軸::直方体の面の軸(箱の軸) => self.直方体の幾何.軸に沿った単位向き(箱の軸),
            直方体と三角形の分離軸::三角形の面の法線 => self.三角形.単位法線の変位(),
            直方体と三角形の分離軸::直方体の軸と三角形の辺の外積の軸 {
                直方体の軸,
                三角形の辺の始まりの頂点,
            } => self
                .直方体の幾何
                .軸に沿った単位向き(直方体の軸)
                .外積(self.辺の単位向き[三角形の辺の始まりの頂点.並びの位置()]),
        }
    }

    pub(super) fn 直方体の幾何(&self) -> &任意姿勢の直方体の倍精度の幾何 {
        self.直方体の幾何
    }

    pub(super) fn 三角形(&self) -> &面の向きを備えた三角形 {
        self.三角形
    }
}
