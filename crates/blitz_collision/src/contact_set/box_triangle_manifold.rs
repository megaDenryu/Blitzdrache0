//! 最小の貫通の軸が決まった後に、直方体と三角形の接触点をどの手順で組み立てるかを選ぶ工程。直方体の面の軸なら
//! 直方体を参照面に、三角形の面の法線なら三角形を参照面にした切り抜き、辺の向きの外積なら辺どうしの1点である。
//!
//! 選ぶことだけを持ち、組み立てそのものは持たない。面の切り抜きは`box_triangle_face_manifold.rs`が、辺どうしの
//! 1点は`box_triangle_edge_contact.rs`が持つ。直方体どうしの側(`box_pair_manifold.rs`)が面の切り抜きを自分の
//! 中に置いているのに対しこちらが外へ出しているのは、参照面と入射面の特徴の型が枝ごとに入れ替わり、面の切り抜きが
//! 1つでなく2つの手順になるためである。

use crate::shape::{任意姿勢の直方体の倍精度の幾何, 面の向きを備えた三角形};

use super::box_triangle_axis::直方体と三角形の分離軸;
use super::box_triangle_edge_contact::直方体の辺と三角形の辺の接触点を組む工程;
use super::box_triangle_face_manifold::直方体と三角形の面の切り抜きの工程;
use super::box_triangle_feature::直方体と三角形の接触の特徴の対;
use super::deepest_axis::最小の貫通の軸;
use super::error::接触点集合の問い合わせエラー;
use super::manifold_builder::接触点を積む器;

pub(super) struct 直方体と三角形の接触点を組む工程<'形の寿命> {
    直方体の幾何: &'形の寿命 任意姿勢の直方体の倍精度の幾何,
    三角形: &'形の寿命 面の向きを備えた三角形,
}

impl<'形の寿命> 直方体と三角形の接触点を組む工程<'形の寿命> {
    pub(super) fn 生成する(
        直方体の幾何: &'形の寿命 任意姿勢の直方体の倍精度の幾何, 三角形: &'形の寿命 面の向きを備えた三角形
    ) -> Self {
        Self {
            直方体の幾何, 三角形
        }
    }

    pub(super) fn 最小の貫通の軸から接触点を積む(
        &self,
        最小の軸: &最小の貫通の軸<直方体と三角形の分離軸>,
    ) -> Result<接触点を積む器<直方体と三角形の接触の特徴の対>, 接触点集合の問い合わせエラー> {
        let 向き = 最小の軸.第1の形から第2の形へ向かう向き();
        let 面の工程 = 直方体と三角形の面の切り抜きの工程::生成する(self.直方体の幾何, self.三角形);
        match 最小の軸.軸() {
            直方体と三角形の分離軸::直方体の面の軸(_) => 面の工程.直方体を参照にして積む(向き),
            直方体と三角形の分離軸::三角形の面の法線 => 面の工程.三角形を参照にして積む(向き),
            直方体と三角形の分離軸::直方体の軸と三角形の辺の外積の軸 {
                直方体の軸,
                三角形の辺の始まりの頂点,
            } => {
                let mut 器 = 接触点を積む器::空から始める();
                器.接触点を1つ積む(
                    直方体の辺と三角形の辺の接触点を組む工程::生成する(self.直方体の幾何, self.三角形).接触点を組む(
                        最小の軸,
                        直方体の軸,
                        三角形の辺の始まりの頂点,
                    )?,
                )?;
                Ok(器)
            }
        }
    }
}
