//! 直方体と三角形の接触の特徴の対: 1つの接触点が、直方体のどの特徴と三角形のどの特徴の間で生まれたかである。
//!
//! 直方体どうしの対と別の型にするのは、三角形の側の綴りが`三角形で当たった特徴`であり、面1つ・辺3本・
//! 頂点3つという別の数え方を持つためである。1つの型へ混ぜると、受け取った側が相手の形の種類を知らずに
//! 綴りを読めるという誤った期待を持つ。
//!
//! 網の中では隣り合う三角形が辺と頂点を共有するため、同じ幾何の特徴が別の三角形の番号で返ることがある。
//! 追跡する側は、どの三角形の綴りであるかを三角形の識別と組にして覚える必要がある。三角形の識別は世界側の
//! 台帳の話であり、衝突数学層のこの型は持たない。

use crate::oriented_box::直方体で当たった特徴;
use crate::triangle::三角形で当たった特徴;

use super::clip_feature_pair::切り抜きの特徴の対;

/// 1つの接触点が、直方体のどの特徴と三角形のどの特徴の間で生まれたか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 直方体と三角形の接触の特徴の対 {
    直方体の特徴: 直方体で当たった特徴,
    三角形の特徴: 三角形で当たった特徴,
}

impl 直方体と三角形の接触の特徴の対 {
    pub(super) fn 生成する(直方体の特徴: 直方体で当たった特徴, 三角形の特徴: 三角形で当たった特徴) -> Self {
        Self {
            直方体の特徴, 三角形の特徴
        }
    }

    // 直方体の面を参照にした切り抜きの対を、形の順へ並べ直す。
    pub(super) fn 直方体を参照にした切り抜きの対から生成する(
        対: 切り抜きの特徴の対<直方体で当たった特徴, 三角形で当たった特徴>,
    ) -> Self {
        Self::生成する(対.参照側の特徴(), 対.入射側の特徴())
    }

    // 三角形を参照にした切り抜きの対を、形の順へ並べ直す。
    pub(super) fn 三角形を参照にした切り抜きの対から生成する(
        対: 切り抜きの特徴の対<三角形で当たった特徴, 直方体で当たった特徴>,
    ) -> Self {
        Self::生成する(対.入射側の特徴(), 対.参照側の特徴())
    }

    /// 直方体の側で、この接触点を生んだ面・辺・頂点。
    pub fn 直方体の特徴(&self) -> 直方体で当たった特徴 {
        self.直方体の特徴
    }

    /// 三角形の側で、この接触点を生んだ面・辺・頂点。
    pub fn 三角形の特徴(&self) -> 三角形で当たった特徴 {
        self.三角形の特徴
    }
}
