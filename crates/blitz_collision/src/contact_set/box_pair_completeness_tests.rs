//! 分離軸の完全性の反証。15本の軸で「離れている」と答えた対が本当に離れていること、および「重なっている」と
//! 答えた対が本当に重なっていることを、分離軸を1本も使わない別の判定と突き合わせる。
//!
//! 突き合わせる相手は線分と直方体の交差だけで組んだ判定である。2つの凸多面体が重なることは、一方の辺が他方を
//! 貫くことと同じである(交わりの多面体のどの頂点も、片方の頂点が相手の中に在るか、片方の辺が相手の面を貫くかの
//! どちらかから来る。始点が中に在る線分も交差として返るため、頂点が中に在る場合もこの判定が拾う)。
//! 根拠と実装は `crates/blitz_collision/src/contact_set/query_fixture.rs` にある。
//!
//! 標本は2つある。1つは種から決まった並びを進む擬似乱数で散らした対であり、姿勢も大きさも位置も広く動かす。
//! もう1つは、姿勢を固定した1つの直方体を格子の上で平行移動させた総当たりであり、離れている側と重なっている側の
//! 境目を密に踏む。どちらも、2つの判定が食い違った対をその場で落とす。

#![allow(clippy::unwrap_used)]

use super::cross_axis_preference::外積の軸へ切り替える優位幅メートル;
use super::generation_margin::接触生成の余白メートル;
use crate::contact_set::box_pair_query::{二つの直方体の重なりの接触点集合, 直方体どうしの接触点集合の問い合わせ};
use crate::shape::任意姿勢の直方体;

use super::query_fixture::{
    余白も優位幅も持たない直方体どうしの問い合わせを組む, 直方体を作る, 線分の交差だけで重なりを判定する, 軸まわりの回転
};
use super::random_box_fixture::無作為の直方体の生成元;

fn 分離軸が重なっていると答えるか(第1: &任意姿勢の直方体, 第2: &任意姿勢の直方体) -> bool {
    let 問い合わせ = 余白も優位幅も持たない直方体どうしの問い合わせを組む(第1, 第2);
    match 問い合わせ.二つの直方体の重なりの接触点集合を求める().unwrap() {
        二つの直方体の重なりの接触点集合::二つの直方体が重なっている(_) => true,
        二つの直方体の重なりの接触点集合::二つの直方体は離れている => false,
    }
}

#[test]
fn 無作為に散らした2000対で分離軸と線分の交差の答えが一致する() {
    let mut 生成元 = 無作為の直方体の生成元::種から始める(0x5eed_1234_abcd_0001);
    let mut 重なった件数 = 0;
    for 番号 in 0..2000 {
        let 第1 = 生成元.次の直方体を作る();
        let 第2 = 生成元.次の直方体を作る();
        let 分離軸の答え = 分離軸が重なっていると答えるか(&第1, &第2);
        let 線分の答え = 線分の交差だけで重なりを判定する(&第1, &第2);
        assert_eq!(分離軸の答え, 線分の答え, "{番号}番目の対で分離軸と線分の交差の答えが食い違った");
        if 分離軸の答え {
            重なった件数 += 1;
        }
    }
    assert!(重なった件数 > 100, "無作為の標本で重なった対が少なすぎる(実測{重なった件数}件)");
}

#[test]
fn 格子の上を総当たりで動かした対で分離軸と線分の交差の答えが一致する() {
    let 静止した箱 = 直方体を作る([0.0, 0.0, 0.0], 軸まわりの回転([0.0, 0.0, 1.0], 30.0), [1.0, 0.6, 0.8]);
    let 刻み: u16 = 13;
    let mut 重なった件数 = 0;
    for 東 in 0..刻み {
        for 天頂 in 0..刻み {
            for 南 in 0..刻み {
                let 中心 = [格子の座標(東, 刻み), 格子の座標(天頂, 刻み), 格子の座標(南, 刻み)];
                let 動く箱 = 直方体を作る(中心, 軸まわりの回転([1.0, 1.0, 0.0], 55.0), [0.5, 0.9, 0.4]);
                let 分離軸の答え = 分離軸が重なっていると答えるか(&静止した箱, &動く箱);
                let 線分の答え = 線分の交差だけで重なりを判定する(&静止した箱, &動く箱);
                assert_eq!(
                    分離軸の答え, 線分の答え,
                    "格子の点({東},{天頂},{南})で分離軸と線分の交差の答えが食い違った"
                );
                if 分離軸の答え {
                    重なった件数 += 1;
                }
            }
        }
    }
    assert!(重なった件数 > 100, "格子の総当たりで重なった対が少なすぎる(実測{重なった件数}件)");
}

// 格子の添字を、マイナス3メートルからプラス3メートルまでの座標へ写す。ずらしを足して格子を原点からわずかに
// 外すのは、面と面がちょうど接する退化した対を踏まないようにするためである。
fn 格子の座標(添字: u16, 刻み: u16) -> f32 {
    let 割合 = f32::from(添字) / f32::from(刻み - 1);
    -3.0 + 6.0 * 割合 + 0.017
}
