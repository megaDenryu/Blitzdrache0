//! 2つの辺の向きの外積で作った軸について、重なりの深さが持つ誤差の上界。
//!
//! この上界が要るのは、2つの辺の向きが平行に近いと外積の長さが小さくなり、長さ1に正した向きの相対誤差が
//! その逆数で育つためである。育った誤差が深さへ乗ると、面の軸が本当は最小であるのに、ほとんど平行な辺の
//! 組が偽の最小として選ばれる。選ばれると接触点が1つになり、面で乗っているはずの箱が1点で支えられて傾く。
//! 深さの比較でこの上界だけ厳しくすることで、誤差の範囲でしか勝てない外積の軸を退ける。
//!
//! 記号。倍精度の演算1回の相対誤差の上限を u = 2のマイナス53乗と書く。2つの直方体の軸ごとの半分の長さの
//! 総和と、中心から相手の形までの隔たりを足した量を尺度 S と書く。外積の長さを |L| と書く。
//!
//! 向きの誤差。直方体自身の軸の成分の絶対誤差は27u以下である(四元数の長さの相対誤差4.5u、割った成分5.5u、
//! 2つの積とその和で27u。導出は `crates/blitz_collision/src/shape/coordinate_limit.rs` にある)。外積の
//! 成分は2つの積の差であるから、両方の軸の誤差が入って 27u かける2かける2 で108u、積そのものの丸めと
//! 差の丸めで4uを足して112u以下である。3成分を合わせた長さの誤差は3の平方根倍で194u以下であり、余裕を
//! 見て200uとする。長さ1に正した向きの誤差はこれを |L| で割った 200u/|L| 以下である。
//!
//! 深さへの伝わり方。深さは、2つの形の射影の区間の端の差である。区間の端は「中心の射影 ± 軸ごとの内積の
//! 絶対値と半分の長さの積の和」であるから、向きを微小に動かしたときの深さの動きは尺度 S に向きの動きを
//! 掛けた量で抑えられる。射影と割り算そのものの丸めは、分子が S かける |L| の大きさで演算が8回以下である
//! から、|L| で割った後で 8u かける S 以下である。
//!
//! したがって上界は S かける (200u/|L| + 8u) である。外積の長さが1に近い(2つの辺の向きが直交に近い)組では
//! S の2のマイナス44乗倍ほどであり、深さの比較を実質的に変えない。長さが2のマイナス20乗まで小さい組では
//! S の2のマイナス24乗倍になり、そこで初めて面の軸が優先される。

// 倍精度の演算1回の相対誤差の上限。2のマイナス53乗であり、隣り合う倍精度の刻み(2のマイナス52乗)の半分である。
const 倍精度の丸めの単位: f64 = f64::EPSILON / 2.0;

// 長さ1に正した外積の向きが持つ、成分の絶対誤差の上界の倍精度の丸めの単位に対する比。
const 外積の向きの誤差の係数: f64 = 200.0;

// 射影と割り算そのものの丸めが深さへ残す量の、倍精度の丸めの単位に対する比。
const 射影の丸めの係数: f64 = 8.0;

pub(super) fn 外積の軸の重なりの誤差の上界を求める(尺度のメートル: f64, 外積の長さ: f64) -> f64 {
    let 向きの誤差 = 外積の向きの誤差の係数 * 倍精度の丸めの単位 / 外積の長さ;
    let 射影の誤差 = 射影の丸めの係数 * 倍精度の丸めの単位;
    尺度のメートル * (向きの誤差 + 射影の誤差)
}
