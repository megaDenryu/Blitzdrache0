//! 2つの辺の向きの外積で作った軸について、重なりの深さが持つ誤差の上界。
//!
//! この上界が要るのは、2つの辺の向きが平行に近いと外積の長さが小さくなり、長さ1に正した向きの相対誤差がその逆数で育つためである。
//! 育った誤差が深さへ乗ると、面の軸が本当は最小であるのに、ほとんど平行な辺の組が偽の最小として選ばれる。
//! 選ばれると接触点が1つになり、面で乗っているはずの箱が1点で支えられて傾く。
//! 深さの比較でこの上界だけ厳しくすることで、誤差の範囲でしか勝てない外積の軸を退ける。
//!
//! ここが数えるのは倍精度の丸めだけであり、これは幾何の誤差である。走査が実際に使う切り替えの余地は、この上界へ
//! 外積の軸へ切り替える優位幅(接触解法向けの選択の方針)を足したものであり、由来の違う2つの和である。
//! 足し算は `crates/blitz_collision/src/contact_set/cross_axis_preference.rs` が行う。
//!
//! 記号と定義域。倍精度の演算1回の相対誤差の上限を u = 2のマイナス53乗と書く。
//! 2つの形の広がりと隔たりを合わせた量を尺度 S と書き、走査の側が「2つの形の半分の長さの総和と中心間の隔たりの和」として渡す。
//! 外積の真の長さを |L| と書き、走査が実際に求めた長さを |L~| と書く。
//! 以下の数えはすべて、走査が通す演算の列(`box_pair_axis_search.rs`・`box_triangle_axis_search.rs`・`box_projection.rs`・`triangle_projection.rs`・`axis_interval.rs`)をそのまま追ったものであり、2次以上の項は最後の丸め上げへ吸収する。
//!
//! 外積を作る2つの向きの誤差。直方体自身の軸は成分の絶対誤差が27u以下である(四元数の長さの相対誤差4.5u、割った成分5.5u、2つの積とその和で27u。導出は `crates/blitz_collision/src/shape/coordinate_limit.rs` にある)。
//! 三角形の辺の単位向きは、頂点の引き算で相対誤差1u、最大の成分で割る工程・長さの二乗の5回・平方根・成分ごとの割り算を通って合わせて相対誤差8u以下であり、成分の絶対値が1以下であるから絶対誤差も8u以下になる。
//! したがって両方を27u以下として数えてよい。
//!
//! 外積の成分の誤差。外積の成分は2つの積の差であるから、2つの向きの誤差が2つずつ入って 27u かける2かける2 で108u、積そのものの丸めと差の丸めで4uを足して112u以下である。
//! 3成分を合わせた長さの誤差は3の平方根倍で194u以下であり、余裕を見て200uとする。
//!
//! 長さ1に正した向きの誤差。分子の誤差だけでなく分母の長さの誤差も入るため、真の外積 L と求めた外積 L~ について次の分解が要る。
//! L~/|L~| ひく L/|L| は (L~ ひく L)/|L| と L~ かける (|L| ひく |L~|)/(|L~| かける |L|) の和である。
//! 後ろの項の大きさは |L| と |L~| の差の絶対値を |L| で割ったものであり、長さの差は変位の差を越えないから前の項と同じ大きさで抑えられる。
//! したがって正した向きの隔たりは 2 かける |L~ ひく L| / |L| 以下、すなわち 400u/|L| 以下である。
//!
//! 求めた長さで真の長さを置き換える余裕。走査は |L| を知らず |L~| を渡すため、係数を800まで広げて2つの場合を同時に覆う。
//! |L~| が400u以上なら |L| は |L~| ひく 200u 以上、すなわち |L~| の半分以上であるから、800u/|L~| が 400u/|L| を上から抑える。
//! |L~| が400u未満なら 800u/|L~| は2を越え、上界は尺度の2倍以上になる。
//! 射影の区間の端は基準点から測って絶対値が S 以下、深さは2つの端の差であるから絶対値が S 以下であり、向きを取り替えたときの深さの差は 2かけるS を越えない。
//! したがってこの側でも上界が成り立つ。
//!
//! 向きの誤差が深さへ伝わる倍率。深さは2つの形の射影の区間の端の差であり、端は「中心の射影 ± 軸ごとの内積の絶対値と半分の長さの積の和」または「3つの頂点の射影の最小と最大」である。
//! どちらも基準点からの隔たりと広がりの和、すなわち S で抑えられるから、向きを微小に動かしたときの深さの動きは S に向きの動きを掛けた量以下になる。
//!
//! 射影と割り算そのものの丸め。直方体の広がりは軸3本それぞれについて、内積の3回の積と2回の加算(中間の値は |L| の3の平方根倍以下)で 5かける3の平方根 かける u かける |L|、軸の成分の27uの誤差が |L| の3の平方根倍に乗って 27かける3の平方根 かける u かける |L|、合わせて56u かける |L| 以下の誤差を持つ。
//! これに半分の長さを掛ける丸め1回を足して57u、3項を足す加算2回で2uを足し、広がり全体で 59u かける |L| かける 半分の長さの総和 以下になる。
//! 中心の射影は3回の引き算と3回の積と2回の加算の8演算であるから 8u かける 中心間の隔たり かける |L| 以下、端を組む加算1回と押す量の引き算1回でさらに 2u かける S かける |L| を足す。
//! 三角形の側は頂点が倍精度のまま入るため入力の誤差を持たず、頂点3つの射影がそれぞれ、基準点を引く3減算を含めた8演算で 8u かける 隔たり かける |L| 以下である。
//! どちらの組でも合計は 68u かける S かける |L| 以下であり(直方体の側は広がりの59uが半分の長さの総和に、中心の射影の8uが隔たりに掛かり、総和と隔たりの和が S である)、これを |L~| で割ると 68u かける S になる。
//! 割る工程そのものは、長さの二乗の5回と平方根と割り算で相対誤差4.5u以下であり、深さが S 以下であるから 4.5u かける S を足す。
//! 合わせて72.5u かける S 以下であり、余裕を見て80uとする。
//!
//! したがって上界は S かける (800u/|L~| + 80u) である。
//! 外積の長さが1に近い(2つの辺の向きが直交に近い)組では S の2のマイナス43乗倍ほどであり、深さの比較を実質的に変えない。
//! 長さが2のマイナス20乗まで小さい組では S の2のマイナス23乗倍になり、そこで初めて面の軸が優先される。

// 倍精度の演算1回の相対誤差の上限。2のマイナス53乗であり、隣り合う倍精度の刻み(2のマイナス52乗)の半分である。
const 倍精度の丸めの単位: f64 = f64::EPSILON / 2.0;

// 長さ1に正した外積の向きが持つ、成分の絶対誤差の上界の倍精度の丸めの単位に対する比。
const 外積の向きの誤差の係数: f64 = 800.0;

// 射影と割り算そのものの丸めが深さへ残す量の、倍精度の丸めの単位に対する比。
const 射影の丸めの係数: f64 = 80.0;

pub(super) fn 外積の軸の重なりの誤差の上界を求める(尺度のメートル: f64, 外積の長さ: f64) -> f64 {
    let 向きの誤差 = 外積の向きの誤差の係数 * 倍精度の丸めの単位 / 外積の長さ;
    let 射影の誤差 = 射影の丸めの係数 * 倍精度の丸めの単位;
    尺度のメートル * (向きの誤差 + 射影の誤差)
}
