//! 2つの形のどちらを参照面の側にしたか。
//!
//! 真偽値で持たないのは、真がどちらの形を指すかを呼び出し側が別の決まりで覚えることになるためである。
//! 切り抜きは参照面と入射面の役しか知らないため、答えを形の順(第1の形・第2の形)へ並べ直すときにこの値が要る。
//!
//! 最小の貫通の軸が第1の形の面の軸なら第1の形が参照であり、第2の形の面の軸なら第2の形が参照である。
//! 共有の単位法線は常に第1の形から第2の形へ向かうため、参照面の外向きの単位法線は、第1の形が参照なら
//! その向きそのもの、第2の形が参照ならその逆向きになる。

use crate::shape::形の局所座標の位置;

/// 2つの形のどちらを参照面の側にしたか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 参照にした側 {
    第1の形,
    第2の形,
}

impl 参照にした側 {
    // 第1の形から第2の形へ向かう向きへ掛けると、参照面の外向きの単位法線になる符号。
    pub(super) fn 参照面の外向きへ揃える符号(self) -> f64 {
        match self {
            Self::第1の形 => 1.0,
            Self::第2の形 => -1.0,
        }
    }

    // 切り抜きが得た2つの点を、形の順へ並べ直したときの第1の形の上の点。
    pub(super) fn 第1の形の上の位置を選ぶ(
        self,
        入射面の上の点: 形の局所座標の位置,
        参照面の上の点: 形の局所座標の位置,
    ) -> 形の局所座標の位置 {
        match self {
            Self::第1の形 => 参照面の上の点,
            Self::第2の形 => 入射面の上の点,
        }
    }

    // 切り抜きが得た2つの点を、形の順へ並べ直したときの第2の形の上の点。
    pub(super) fn 第2の形の上の位置を選ぶ(
        self,
        入射面の上の点: 形の局所座標の位置,
        参照面の上の点: 形の局所座標の位置,
    ) -> 形の局所座標の位置 {
        match self {
            Self::第1の形 => 入射面の上の点,
            Self::第2の形 => 参照面の上の点,
        }
    }
}
