//! 面で乗る・辺で乗る・頂点で触れる・斜めに食い込むという、参照面の切り抜きが答えを作る場面の反証。
//!
//! 期待する接触点の数が場面ごとに違うことがこの群の要点である。切り抜きは常に入射面の輪郭を切り取って
//! 最大4つの点を作るが、参照面の平面より外側に残った点を落とすため、傾いた直方体では2つや1つに減る。
//! 落とす工程を無効にすると、この群の期待値が数の側で落ちる。

#![allow(clippy::unwrap_used)]

use super::box_pair_answer_fixture::{床を作る, 貫通量を並べる, 重なりの集合を求める};
use super::query_fixture::{位置の成分, 回転なし, 直方体を作る, 軸まわりの回転};

#[test]
fn 面で乗る直方体は4つの接触点を持つ() {
    let 床 = 床を作る();
    let 箱 = 直方体を作る([0.0, 0.9, 0.0], 回転なし(), [1.0, 1.0, 1.0]);
    let 集合 = 重なりの集合を求める(&箱, &床);
    assert_eq!(集合.件数(), 4, "面で乗る直方体の接触点が4つでない");
    for 量 in 貫通量を並べる(&集合) {
        assert!((量 - 0.1).abs() < 1e-6, "面で乗る直方体の貫通量が0.1から離れている(実測{量})");
    }
    let 法線 = 集合.共有の単位法線();
    assert!(
        法線.x().abs() < 1e-6 && (法線.y() + 1.0).abs() < 1e-6 && 法線.z().abs() < 1e-6,
        "箱から床へ向かう単位法線が真下を向いていない"
    );
    for 点 in 集合.接触点を順に並べる() {
        let 床の側 = 位置の成分(点.第2の形の上の位置());
        assert!(床の側[1].abs() < 1e-9, "床の側の接触点が床の上面に乗っていない");
        assert!(
            床の側[0].abs() - 1.0 < 1e-9 && 床の側[2].abs() - 1.0 < 1e-9,
            "床の側の接触点が箱の足元から外れている"
        );
    }
}

#[test]
fn 辺で乗る直方体は2つの接触点を持つ() {
    let 床 = 床を作る();
    let 沈み = 0.05;
    let 箱 = 直方体を作る(
        [0.0, (2.0_f32).sqrt() - 沈み, 0.0],
        軸まわりの回転([0.0, 0.0, 1.0], 45.0),
        [1.0, 1.0, 1.0],
    );
    let 集合 = 重なりの集合を求める(&箱, &床);
    assert_eq!(集合.件数(), 2, "辺で乗る直方体の接触点が2つでない");
    for 量 in 貫通量を並べる(&集合) {
        assert!(
            (量 - f64::from(沈み)).abs() < 1e-5,
            "辺で乗る直方体の貫通量が沈みから離れている(実測{量})"
        );
    }
}

