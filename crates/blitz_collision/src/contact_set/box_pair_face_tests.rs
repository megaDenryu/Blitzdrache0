#[test]
fn 斜めに食い込む直方体は下の辺の2つの接触点を持つ() {
    let 床 = 床を作る();
    let 箱 = 直方体を作る([0.0, 0.5, 0.0], 軸まわりの回転([0.0, 0.0, 1.0], 45.0), [1.0, 1.0, 1.0]);
    let 集合 = 重なりの集合を求める(&箱, &床);
    assert_eq!(集合.件数(), 2, "斜めに食い込む直方体の接触点が2つでない");
    let 期待する貫通量 = (2.0_f64).sqrt() - 0.5;
    for 量 in 貫通量を並べる(&集合) {
        assert!(
            (量 - 期待する貫通量).abs() < 1e-5,
            "斜めに食い込む直方体の貫通量が期待から離れている(実測{量}、期待{期待する貫通量})"
        );
    }
}

#[test]
fn 同一の直方体は4つの接触点を持ち貫通量が一辺に等しい() {
    let 箱 = 直方体を作る([0.0, 0.0, 0.0], 回転なし(), [1.0, 1.0, 1.0]);
    let 集合 = 重なりの集合を求める(&箱, &箱);
    assert_eq!(集合.件数(), 4, "同一の直方体の接触点が4つでない");
    for 量 in 貫通量を並べる(&集合) {
        assert!((量 - 2.0).abs() < 1e-9, "同一の直方体の貫通量が一辺の長さでない(実測{量})");
    }
}
