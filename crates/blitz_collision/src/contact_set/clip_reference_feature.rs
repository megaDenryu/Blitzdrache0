//! 参照面の側の平面が切り取った点について、参照側の特徴をどう名付けるかの決まり。直方体の綴りと三角形の綴りがそれぞれ実装する。
//!
//! 決まりを形ごとの実装にするのは、切り抜きが形の種類を知らずに走るためである。
//! 切り抜きが知っているのは「参照面を囲む1本の辺で切り取った」ことだけであり、その辺と、2本の辺が交わる角にどんな名前が付くかは形の側の綴りが決める。
//!
//! 2本目の辺で切り取る場面がこの決まりの要点である。
//! 最初の側の平面が作った境界の辺は「参照面の1本の辺と入射面」の特徴を持ち、その境界の辺を次の側の平面が横切る点は2本の参照面の辺が交わる参照面の角である。
//! 角は辺ではなく頂点であり、直方体の参照面なら直方体の頂点、三角形の参照面なら三角形の頂点になる。
//! どちらの名前でも接触点の位置は同じであるが、名前が違うと次の刻みで同じ接触を指す識別が壊れる。
//! 識別が追跡の綴りになる理由は `crates/blitz_collision/src/contact_set/box_pair_feature.rs` にある。
//!
//! 角をもう1本の辺で切り取る場面は、参照面の角をちょうど通る側の平面でしか起こらない退化した配置である。
//! そのときは既に持っている角の名前を残す。角より細かい特徴が参照面に無いためである。

use crate::oriented_box::{直方体で当たった特徴, 直方体の辺};
use crate::shape::三角形の頂点の番号;
use crate::triangle::三角形で当たった特徴;

use super::box_feature_support::二つの辺が共有する頂点を組む;

pub(super) trait 参照面の辺で切り取った点の特徴の綴り: Copy {
    /// 参照面を囲む1本の辺を指す綴り。直方体なら直方体の辺、三角形なら辺の始まりの頂点の番号である。
    type 参照面を囲む辺: Copy + core::fmt::Debug + PartialEq;

    // まだ切り取られていない点を、参照面を囲む1本の辺で切り取ったときの参照側の特徴。
    fn 参照面を囲む辺そのものの特徴を組む(辺: Self::参照面を囲む辺) -> Self;

    // この特徴を持つ点を、参照面を囲むもう1本の辺で切り取ったときの参照側の特徴。
    fn もう1本の辺で切り取った点の特徴を求める(self, 切り取る辺: Self::参照面を囲む辺) -> Self;
}

impl 参照面の辺で切り取った点の特徴の綴り for 直方体で当たった特徴 {
    type 参照面を囲む辺 = 直方体の辺;

    fn 参照面を囲む辺そのものの特徴を組む(辺: 直方体の辺) -> Self {
        Self::直方体の辺(辺)
    }

    fn もう1本の辺で切り取った点の特徴を求める(self, 切り取る辺: 直方体の辺) -> Self {
        match self {
            Self::直方体の面(_) => Self::直方体の辺(切り取る辺),
            Self::直方体の辺(これまでの辺) => {
                二つの辺が共有する頂点を組む(これまでの辺, 切り取る辺).map_or(Self::直方体の辺(切り取る辺), Self::直方体の頂点)
            }
            Self::直方体の頂点(_) => self,
        }
    }
}

impl 参照面の辺で切り取った点の特徴の綴り for 三角形で当たった特徴 {
    type 参照面を囲む辺 = 三角形の頂点の番号;

    fn 参照面を囲む辺そのものの特徴を組む(始まりの頂点: 三角形の頂点の番号) -> Self {
        Self::三角形の辺 { 始まりの頂点 }
    }

    fn もう1本の辺で切り取った点の特徴を求める(self, 切り取る辺: 三角形の頂点の番号) -> Self {
        match self {
            Self::三角形の面 => Self::三角形の辺 {
                始まりの頂点: 切り取る辺
            },
            Self::三角形の辺 { 始まりの頂点 } => 三角形の二つの辺が共有する頂点を組む(始まりの頂点, 切り取る辺),
            Self::三角形の頂点(_) => self,
        }
    }
}

// 三角形の2本の辺が共有する頂点。辺は始まりの頂点から次の番号の頂点へ張るため、次の番号の辺とは後ろの頂点を、
// その次の番号の辺とは前の頂点を共有する。同じ辺を2度通った入力は頂点を1つに定められないため、その辺を返す。
fn 三角形の二つの辺が共有する頂点を組む(
    始まりの頂点: 三角形の頂点の番号,
    もう一方の始まりの頂点: 三角形の頂点の番号,
) -> 三角形で当たった特徴 {
    if 始まりの頂点 == もう一方の始まりの頂点 {
        return 三角形で当たった特徴::三角形の辺 { 始まりの頂点 };
    }
    if もう一方の始まりの頂点 == 始まりの頂点.次の頂点() {
        return 三角形で当たった特徴::三角形の頂点(もう一方の始まりの頂点);
    }
    三角形で当たった特徴::三角形の頂点(始まりの頂点)
}
