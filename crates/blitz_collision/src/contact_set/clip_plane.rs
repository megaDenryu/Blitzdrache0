//! 参照面の側の平面と、その平面1つで多角形を切り抜く工程。
//!
//! 参照面の側の平面とは、参照面に垂直で参照面の1辺を通る平面のことである。参照面が直方体の面なら4つ、
//! 三角形なら3つある。入射面の輪郭をこれらの平面の内側へ順に切り詰めた結果が、接触点の候補になる。
//!
//! 法線の長さを1に正さないのは、この平面が符号と比だけに使われるためである。内側かどうかは符号で決まり、
//! 交点の位置は2つの隔たりの比で決まるから、どちらも法線の長さを掛けても変わらない。三角形の側の平面の
//! 法線は「面に垂直な変位と辺の変位の外積」であり、正すには平方根が3回要る。
//!
//! 切り抜きは1つの平面につき、入射面の輪郭を1周する。内側に在る頂点をそのまま残し、内側と外側をまたぐ辺の
//! 上に新しい頂点を作る。新しい頂点の入射側の特徴は、またいだ辺の入射側の特徴である。
//!
//! 新しい頂点の参照側の特徴は、またいだ辺が参照側に何を持っていたかで決まる。まだ切り取られていない辺を
//! またいだなら、その点は参照面のこの辺の上に在るからこの辺になる。先の平面が作った境界の辺をまたいだなら、
//! その点は2本の参照面の辺が交わる参照面の角であるから頂点になる。決まりと理由は
//! `crates/blitz_collision/src/contact_set/clip_reference_feature.rs` にある。
//!
//! 外へ出る側で作った新しい頂点は、そこから輪郭がこの平面の上を進むため、次の辺の特徴の対を「この平面の辺と
//! 入射面そのもの」にする。内へ入る側で作った新しい頂点は、そこから元の辺の残りを進むため、またいだ辺の
//! 特徴の対をそのまま引き継ぐ。

use crate::shape::{形の局所座標の位置, 形の局所座標の変位};

use super::clip_feature_pair::切り抜きの特徴の対;
use super::clip_polygon::{切り抜き中の多角形, 多角形の頂点};
use super::clip_reference_feature::参照面の辺で切り取った点の特徴の綴り;
use super::error::接触点集合の問い合わせエラー;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 参照面の側の平面<参照側の特徴: 参照面の辺で切り取った点の特徴の綴り> {
    基準点: 形の局所座標の位置,
    内向きの法線: 形の局所座標の変位,
    切り取る辺: 参照側の特徴::参照面を囲む辺,
}

impl<参照側の特徴: 参照面の辺で切り取った点の特徴の綴り> 参照面の側の平面<参照側の特徴> {
    pub(super) fn 生成する(
        基準点: 形の局所座標の位置, 内向きの法線: 形の局所座標の変位, 切り取る辺: 参照側の特徴::参照面を囲む辺
    ) -> Self {
        Self {
            基準点,
            内向きの法線,
            切り取る辺,
        }
    }

    // 平面から内側へ測った符号付きの隔たり。0以上なら内側である。長さを1に正していない法線で測るため、
    // 値そのものは長さではない。符号と、2つの値の比だけを使う。
    fn 内側からの符号付き隔たりを求める(&self, 点: 形の局所座標の位置) -> f64 {
        self.基準点.終点までの変位を求める(点).内積(self.内向きの法線)
    }

    pub(super) fn この平面で多角形を切り抜く<入射側の特徴: Copy>(
        &self,
        多角形: &切り抜き中の多角形<参照側の特徴, 入射側の特徴>,
        入射面そのものの特徴: 入射側の特徴,
    ) -> Result<切り抜き中の多角形<参照側の特徴, 入射側の特徴>, 接触点集合の問い合わせエラー> {
        let mut 出力 = 切り抜き中の多角形::空から始める();
        if 多角形.件数() == 0 {
            return Ok(出力);
        }
        for 番号 in 0..多角形.件数() {
            let (Some(現在), Some(次)) = (多角形.番号の頂点(番号), 多角形.番号の頂点((番号 + 1) % 多角形.件数())) else {
                continue;
            };
            let 現在の隔たり = self.内側からの符号付き隔たりを求める(現在.位置());
            let 次の隔たり = self.内側からの符号付き隔たりを求める(次.位置());
            if 現在の隔たり >= 0.0 {
                出力.頂点を1つ積む(現在)?;
            }
            if (現在の隔たり >= 0.0) != (次の隔たり >= 0.0) {
                出力.頂点を1つ積む(self.またいだ辺の上の頂点を組む(現在, 次, 現在の隔たり, 次の隔たり, 入射面そのものの特徴)?)?;
            }
        }
        Ok(出力)
    }

    // 内側と外側をまたぐ辺の上に、この平面との交点の頂点を組む。
    fn またいだ辺の上の頂点を組む<入射側の特徴: Copy>(
        &self,
        現在: 多角形の頂点<参照側の特徴, 入射側の特徴>,
        次: 多角形の頂点<参照側の特徴, 入射側の特徴>,
        現在の隔たり: f64,
        次の隔たり: f64,
        入射面そのものの特徴: 入射側の特徴,
    ) -> Result<多角形の頂点<参照側の特徴, 入射側の特徴>, 接触点集合の問い合わせエラー> {
        let 比 = 現在の隔たり / (現在の隔たり - 次の隔たり);
        let 位置 = 現在
            .位置()
            .変位だけ進んだ位置を求める(現在.位置().終点までの変位を求める(次.位置()).実数倍する(比))?;
        let またいだ辺の特徴 = 現在.次の頂点への辺の特徴の対();
        let 頂点の特徴 = 切り抜きの特徴の対::生成する(
            またいだ辺の特徴.参照側の特徴().もう1本の辺で切り取った点の特徴を求める(self.切り取る辺),
            またいだ辺の特徴.入射側の特徴(),
        );
        let 次の辺の特徴 = if 現在の隔たり >= 0.0 {
            切り抜きの特徴の対::生成する(参照側の特徴::参照面を囲む辺そのものの特徴を組む(self.切り取る辺), 入射面そのものの特徴)
        } else {
            またいだ辺の特徴
        };
        Ok(多角形の頂点::生成する(位置, 頂点の特徴, 次の辺の特徴))
    }
}
