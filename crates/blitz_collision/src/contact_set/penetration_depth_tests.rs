//! 貫通量の符号の反証。負の値と有限でない値を型付きエラーで拒み、0と正の値を受け入れることを見る。
//!
//! 型の入口で拒むことに反証を置くのは、切り抜きが参照面の外側に残った点を落とす工程がこの拒否に乗っている
//! ためである。拒否を素通しにすると、触れていない角に力を掛ける接触点が集合へ入る。

#![allow(clippy::unwrap_used)]

use crate::contact_set::error::接触点集合の問い合わせエラー;
use crate::contact_set::penetration_depth::貫通量メートル;

#[test]
fn 負の貫通量と有限でない貫通量は型付きエラーで拒まれる() {
    for 値 in [-1.0, -f64::MIN_POSITIVE, f64::NAN, f64::INFINITY, f64::NEG_INFINITY] {
        assert_eq!(
            貫通量メートル::生成する(値),
            Err(接触点集合の問い合わせエラー::貫通量が負であるか有限でない),
            "貫通量として拒むべき値{値}が通った"
        );
    }
}

#[test]
fn 零と正の貫通量は受け入れられる() {
    for 値 in [0.0, f64::MIN_POSITIVE, 0.25, 1.0e6] {
        assert_eq!(貫通量メートル::生成する(値).unwrap().値(), 値, "貫通量として受け入れた値が変わった");
    }
}
