//! 符号付き貫通量が接触生成の余白で決まる定義域を持つことの反証。余白より外の値と有限でない値を型付きエラーで拒み、
//! 余白の内側の負の値と0と正の値を受け入れることを見る。
//!
//! 型の入口で拒むことに反証を置くのは、切り抜きが参照面の外側に残った点を落とす工程がこの拒否に乗っている
//! ためである。拒否を素通しにすると、余白より遠くで触れていない角に力を掛ける接触点が集合へ入る。

#![allow(clippy::unwrap_used)]

use crate::contact_set::error::接触点集合の問い合わせエラー;
use crate::contact_set::generation_margin::接触生成の余白メートル;
use crate::contact_set::penetration_depth::符号付き貫通量メートル;

#[test]
fn 余白より外の値と有限でない値は型付きエラーで拒まれる() {
    let 余白 = 接触生成の余白メートル::生成する(0.005).unwrap();
    for 値 in [-0.005_001, -1.0, f64::NAN, f64::INFINITY, f64::NEG_INFINITY] {
        assert_eq!(
            符号付き貫通量メートル::余白の内側であることを確かめて生成する(値, 余白),
            Err(接触点集合の問い合わせエラー::貫通量が余白より外であるか有限でない),
            "符号付き貫通量として拒むべき値{値}が通った"
        );
    }
}

#[test]
fn 余白の内側の負の値と零と正の値は受け入れられる() {
    let 余白 = 接触生成の余白メートル::生成する(0.005).unwrap();
    for 値 in [-0.005, -0.001, 0.0, f64::MIN_POSITIVE, 0.25, 1.0e6] {
        assert_eq!(
            符号付き貫通量メートル::余白の内側であることを確かめて生成する(値, 余白).unwrap().値(),
            値,
            "符号付き貫通量として受け入れた値が変わった"
        );
    }
}

#[test]
fn 余白を持たない問い合わせは負の値を拒み接しているだけの点を受け入れる() {
    let 余白 = 接触生成の余白メートル::余白を持たない();
    assert_eq!(
        符号付き貫通量メートル::余白の内側であることを確かめて生成する(-f64::MIN_POSITIVE, 余白),
        Err(接触点集合の問い合わせエラー::貫通量が余白より外であるか有限でない),
        "余白を持たない問い合わせが負の符号付き貫通量を受け入れた"
    );
    assert_eq!(
        符号付き貫通量メートル::余白の内側であることを確かめて生成する(0.0, 余白).unwrap().値(),
        0.0,
        "余白を持たない問い合わせが接しているだけの点を拒んだ"
    );
}

#[test]
fn 負の余白と有限でない余白は型付きエラーで拒まれる() {
    for 値 in [-f64::MIN_POSITIVE, -1.0, f64::NAN, f64::INFINITY] {
        assert_eq!(
            接触生成の余白メートル::生成する(値),
            Err(接触点集合の問い合わせエラー::接触生成の余白が負であるか有限でない),
            "接触生成の余白として拒むべき値{値}が通った"
        );
    }
}
