//! 塔に積んだ同じ大きさの立方体の反証。接する面が完全に平行で完全に重なっている配置と、そこから微小に傾けた
//! 配置で、接触点が4つ残ることと、余白を外した反証では残らないことを見る。
//!
//! この群を面の反証(`box_pair_face_tests.rs`)と別に置くのは、あちらが「参照面の外に出た角を落とすこと」を
//! 固定しているのに対し、こちらは「接触生成の余白の内側に居る角を落とさないこと」を固定するためである。
//! 2つは同じ工程の両側であり、片方だけでは余白が広すぎても狭すぎても落ちない。
//!
//! 傾きの境目は幾何から決まる。半分の長さ0.5メートルの立方体では、傾き θ が上の箱の角を 0.5 sin θ だけ
//! 持ち上げるため、余白を持たない問い合わせは sin θ が 食い込み ÷ 0.5 を超えた時点で4つのうち2つを落とし、
//! 余白のある問い合わせは (食い込み + 余白) ÷ 0.5 を超えるまで落とさない。
//! 参照: `crates/blitz_collision/src/contact_set/generation_margin.rs`

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{クォータニオン, ローカル};

use crate::oriented_box::直方体で当たった特徴;

use super::box_pair_query::{二つの直方体の重なりの接触点集合, 直方体どうしの接触点集合の問い合わせ};
use super::generation_margin::接触生成の余白メートル;
use super::query_fixture::{回転なし, 直方体を作る};

const 半分の長さ: f32 = 0.5;
const 食い込み: f32 = 0.001;
const 塔の余白: f64 = 0.005;

fn 塔の余白を持つ問い合わせの余白() -> 接触生成の余白メートル {
    接触生成の余白メートル::生成する(塔の余白).unwrap()
}

// 下の立方体の上に、面を合わせて食い込みのぶんだけ沈めた立方体を置き、上の立方体を鉛直面内で傾ける。
fn 積んだ二つの立方体の接触点の数と特徴(
    傾きの度: f32,
    余白: 接触生成の余白メートル,
) -> (usize, Vec<(直方体で当たった特徴, 直方体で当たった特徴)>) {
    let 下 = 直方体を作る([0.0, 半分の長さ, 0.0], 回転なし(), [半分の長さ; 3]);
    let 上 = 直方体を作る([0.0, 半分の長さ * 3.0 - 食い込み, 0.0], 鉛直面内で傾ける(傾きの度), [半分の長さ; 3]);
    let 問い合わせ = 直方体どうしの接触点集合の問い合わせ::二つの直方体と余白から生成する(&下, &上, 余白);
    match 問い合わせ.二つの直方体の重なりの接触点集合を求める().unwrap() {
        二つの直方体の重なりの接触点集合::二つの直方体は離れている => panic!("積んだ立方体が離れていると答えた"),
        二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) => (
            集合.件数(),
            集合
                .接触解法の候補点を順に並べる()
                .map(|点| (点.特徴の識別().第1の直方体の特徴(), 点.特徴の識別().第2の直方体の特徴()))
                .collect(),
        ),
    }
}

fn 鉛直面内で傾ける(度: f32) -> クォータニオン<ローカル, ローカル> {
    if 度 == 0.0 {
        return 回転なし();
    }
    let 半角 = 度.to_radians() / 2.0;
    クォータニオン::生成する(0.0, 0.0, 半角.sin(), 半角.cos()).unwrap()
}

#[test]
fn 平行に重なった同じ大きさの二つの立方体は面と面の四隅の四点を返す() {
    let (件数, 特徴) = 積んだ二つの立方体の接触点の数と特徴(0.0, 塔の余白を持つ問い合わせの余白());
    assert_eq!(件数, 4, "平行に重なった立方体の接触点が4つでない");
    for (下の特徴, 上の特徴) in 特徴 {
        assert!(
            matches!(下の特徴, 直方体で当たった特徴::直方体の面(_)),
            "下の立方体の側の特徴が面でない(実測{下の特徴:?})"
        );
        assert!(
            matches!(上の特徴, 直方体で当たった特徴::直方体の頂点(_)),
            "上の立方体の側の特徴が頂点でない(実測{上の特徴:?})"
        );
    }
}

#[test]
fn 食い込みより大きく角を持ち上げる傾きでも余白の内側なら四点を保つ() {
    for 度 in [0.15_f32, 0.3, 0.6, -0.15, -0.3, -0.6] {
        let (件数, _) = 積んだ二つの立方体の接触点の数と特徴(度, 塔の余白を持つ問い合わせの余白());
        assert_eq!(件数, 4, "傾き{度}度で接触点が4つでない");
    }
}

#[test]
fn 余白を外した反証では同じ傾きで接触点が二つに減る() {
    for 度 in [0.15_f32, 0.3, 0.6, -0.15, -0.3, -0.6] {
        let (件数, _) = 積んだ二つの立方体の接触点の数と特徴(度, 接触生成の余白メートル::余白を持たない());
        assert_eq!(件数, 2, "余白を外した反証が傾き{度}度で2つに減っていない");
    }
}

#[test]
fn 余白より遠く角を持ち上げる傾きでは接触点が二つに減る() {
    for 度 in [1.0_f32, 3.0, -1.0, -3.0] {
        let (件数, _) = 積んだ二つの立方体の接触点の数と特徴(度, 塔の余白を持つ問い合わせの余白());
        assert_eq!(件数, 2, "傾き{度}度で余白より遠い角が落ちていない");
    }
}
