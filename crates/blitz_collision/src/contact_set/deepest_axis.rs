//! 最小の貫通の軸と、候補を1本ずつ数えてそれを選ぶ器。
//!
//! 器と結果を同じところへ置くのは、器がこの結果を組み立てるためだけに在り、途中の状態(まだ何も数えていない
//! 状態)を結果の型が持たないためである。切り離すと、選ぶ決まりと選ばれた値が別の場所に散る。
//!
//! 面の軸と外積の軸で入れ替えの決まりが違う。面の軸は厳密な比較で入れ替え、外積の軸は渡された余地だけ小さく
//! なければ入れ替えない。並びが面の軸を先に置くため、深さが等しい面の軸と外積の軸では面の軸が残る。
//! 余地の中身は走査の側が決める。倍精度の丸めが作る偽の最小を退ける幾何の誤差の上界
//! (`crates/blitz_collision/src/contact_set/cross_axis_margin.rs`)と、接触解法向けの選択の方針である
//! 外積の軸へ切り替える優位幅(`crates/blitz_collision/src/contact_set/cross_axis_preference.rs`)の和である。
//! この器が覚える軸は幾何の最小そのものではなく、参照面として使う軸である。
//!
//! 軸の向きは、第1の形から第2の形へ向かうように反転を済ませたものを受け取る。長さ1に正すのは、答えを
//! 組む1箇所へ寄せるためであり、ここでは正していない向きを持ち回る。深さは正した向きで測った長さである。

use crate::shape::形の局所座標の変位;

/// 分離軸のうち重なりが最も浅かった1本。その軸と深さと、第1の形から第2の形へ向かう向きを持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 最小の貫通の軸<軸> {
    軸: 軸,
    重なりの深さのメートル: f64,
    第1の形から第2の形へ向かう向き: 形の局所座標の変位,
}

impl<軸: Copy> 最小の貫通の軸<軸> {
    pub(super) fn 軸(&self) -> 軸 {
        self.軸
    }

    pub(super) fn 重なりの深さのメートル(&self) -> f64 {
        self.重なりの深さのメートル
    }

    pub(super) fn 第1の形から第2の形へ向かう向き(&self) -> 形の局所座標の変位 {
        self.第1の形から第2の形へ向かう向き
    }
}

pub(super) struct 最も浅い重なりの軸だけを覚える器<軸> {
    覚えている軸: Option<最小の貫通の軸<軸>>,
}

impl<軸: Copy> 最も浅い重なりの軸だけを覚える器<軸> {
    pub(super) fn まだ何も無い状態から始める() -> Self {
        Self { 覚えている軸: None }
    }

    // 面の軸を1本数える。今の最小より厳密に浅ければ入れ替える。
    pub(super) fn 面の軸を1本数える(&mut self, 軸: 軸, 深さ: f64, 向き: 形の局所座標の変位) {
        self.入れ替えの余地だけ小さければ覚え直す(軸, 深さ, 向き, 0.0);
    }

    // 外積の軸を1本数える。渡された入れ替えの余地だけ小さくなければ入れ替えない。余地の中身は走査の側が決める。
    pub(super) fn 外積の軸を1本数える(&mut self, 軸: 軸, 深さ: f64, 向き: 形の局所座標の変位, 入れ替えの余地: f64) {
        self.入れ替えの余地だけ小さければ覚え直す(軸, 深さ, 向き, 入れ替えの余地);
    }

    fn 入れ替えの余地だけ小さければ覚え直す(&mut self, 軸: 軸, 深さ: f64, 向き: 形の局所座標の変位, 余地: f64) {
        let 入れ替える = match &self.覚えている軸 {
            None => true,
            Some(これまで) => 深さ + 余地 < これまで.重なりの深さのメートル,
        };
        if 入れ替える {
            self.覚えている軸 = Some(最小の貫通の軸 {
                軸,
                重なりの深さのメートル: 深さ,
                第1の形から第2の形へ向かう向き: 向き,
            });
        }
    }

    pub(super) fn 覚えている軸を取り出す(self) -> Option<最小の貫通の軸<軸>> {
        self.覚えている軸
    }
}
