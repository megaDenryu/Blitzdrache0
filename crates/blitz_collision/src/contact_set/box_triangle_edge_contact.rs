//! 最小の貫通の軸が直方体の辺の向きと三角形の辺の向きの外積であるときの、1点だけの接触点を組む工程。
//!
//! 直方体どうしの辺の組(`edge_pair_contact.rs`)と同じ役であり、違うのは相手の辺の出どころだけである。
//! 直方体の側は軸の向きへ最も遠い辺を選ぶが、三角形の側は分離軸が指す辺そのものである。三角形は3辺しか
//! 持たず、どれが軸の向きへ遠いかを選ぶ余地が無い。
//!
//! 貫通量は軸の上で測った重なりの深さである。2つの点の隔たりから求め直さないのは、隔たりが軸に垂直な成分を
//! 含みうるためであり、この層が答えるのは軸に沿った食い込みだからである。

use crate::oriented_box::直方体で当たった特徴;
use crate::shape::{
    三角形の頂点の番号, 任意姿勢の直方体の倍精度の幾何, 直方体自身の座標軸, 面の向きを備えた三角形
};
use crate::triangle::三角形で当たった特徴;

use super::box_triangle_axis::直方体と三角形の分離軸;
use super::box_triangle_feature::直方体と三角形の接触の特徴の対;
use super::contact_point::接触点;
use super::deepest_axis::最小の貫通の軸;
use super::error::接触点集合の問い合わせエラー;
use super::penetration_depth::貫通量メートル;
use super::segment_pair_point::二つの線分の最近接の点;

pub(super) struct 直方体の辺と三角形の辺の接触点を組む工程<'形の寿命> {
    直方体の幾何: &'形の寿命 任意姿勢の直方体の倍精度の幾何,
    三角形: &'形の寿命 面の向きを備えた三角形,
}

impl<'形の寿命> 直方体の辺と三角形の辺の接触点を組む工程<'形の寿命> {
    pub(super) fn 生成する(
        直方体の幾何: &'形の寿命 任意姿勢の直方体の倍精度の幾何, 三角形: &'形の寿命 面の向きを備えた三角形
    ) -> Self {
        Self {
            直方体の幾何, 三角形
        }
    }

    pub(super) fn 接触点を組む(
        &self,
        最小の軸: &最小の貫通の軸<直方体と三角形の分離軸>,
        直方体の沿う軸: 直方体自身の座標軸,
        三角形の辺の始まりの頂点: 三角形の頂点の番号,
    ) -> Result<接触点<直方体と三角形の接触の特徴の対>, 接触点集合の問い合わせエラー> {
        let 辺 = self
            .直方体の幾何
            .沿う軸を決めて向きへ最も遠い辺を求める(直方体の沿う軸, 最小の軸.第1の形から第2の形へ向かう向き());
        let 最近接 = 二つの線分の最近接の点::二本の線分から求める(
            self.直方体の幾何.辺の始点の位置を求める(辺),
            self.直方体の幾何.辺の変位を求める(辺),
            self.三角形.頂点の位置(三角形の辺の始まりの頂点),
            self.三角形.辺の変位を求める(三角形の辺の始まりの頂点),
        );
        Ok(接触点::生成する(
            最近接.第1の線分の上の点(),
            最近接.第2の線分の上の点(),
            貫通量メートル::生成する(最小の軸.重なりの深さのメートル())?,
            直方体と三角形の接触の特徴の対::生成する(
                直方体で当たった特徴::直方体の辺(辺),
                三角形で当たった特徴::三角形の辺 {
                    始まりの頂点: 三角形の辺の始まりの頂点,
                },
            ),
        ))
    }
}
