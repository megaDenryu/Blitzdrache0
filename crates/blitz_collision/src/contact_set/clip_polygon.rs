//! 切り抜きの途中の多角形と、その頂点。入射面の輪郭を参照面の側の平面で順に切り取っていく器である。
//!
//! 頂点と多角形を同じところへ置くのは、頂点が「次の頂点へ向かう辺の特徴」を持ち、その辺が多角形の並びの
//! 中でしか意味を持たないためである。切り離すと、辺の相手がどの頂点かを呼び出し側が覚えることになる。
//!
//! 頂点が自分の特徴の対と辺の特徴の対を両方持つのは、切り抜きが作る新しい頂点の特徴が、切り取った側の平面の
//! 辺と、切り取られた辺の入射側の特徴の組になるためである。辺の特徴を持たないと、その入射側が復元できない。
//!
//! 受け皿の長さは接触点の上限と同じである。凸な多角形を1つの半平面で切り抜いた結果の頂点数が、もとの頂点数に
//! 高々1を足したものであることから導いた上界であり、導出は
//! `crates/blitz_collision/src/contact_set/manifold_capacity.rs` にある。

use crate::shape::形の局所座標の位置;

use super::clip_feature_pair::切り抜きの特徴の対;
use super::error::接触点集合の問い合わせエラー;
use super::manifold_capacity::接触点の上限;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 多角形の頂点<参照側の特徴: Copy, 入射側の特徴: Copy> {
    位置: 形の局所座標の位置,
    この頂点の特徴の対: 切り抜きの特徴の対<参照側の特徴, 入射側の特徴>,
    次の頂点への辺の特徴の対: 切り抜きの特徴の対<参照側の特徴, 入射側の特徴>,
}

impl<参照側の特徴: Copy, 入射側の特徴: Copy> 多角形の頂点<参照側の特徴, 入射側の特徴> {
    pub(super) fn 生成する(
        位置: 形の局所座標の位置,
        この頂点の特徴の対: 切り抜きの特徴の対<参照側の特徴, 入射側の特徴>,
        次の頂点への辺の特徴の対: 切り抜きの特徴の対<参照側の特徴, 入射側の特徴>,
    ) -> Self {
        Self {
            位置,
            この頂点の特徴の対,
            次の頂点への辺の特徴の対,
        }
    }

    pub(super) fn 位置(&self) -> 形の局所座標の位置 {
        self.位置
    }

    pub(super) fn この頂点の特徴の対(&self) -> 切り抜きの特徴の対<参照側の特徴, 入射側の特徴> {
        self.この頂点の特徴の対
    }

    pub(super) fn 次の頂点への辺の特徴の対(&self) -> 切り抜きの特徴の対<参照側の特徴, 入射側の特徴> {
        self.次の頂点への辺の特徴の対
    }
}

pub(super) struct 切り抜き中の多角形<参照側の特徴: Copy, 入射側の特徴: Copy> {
    頂点: [Option<多角形の頂点<参照側の特徴, 入射側の特徴>>; 接触点の上限],
    件数: usize,
}

impl<参照側の特徴: Copy, 入射側の特徴: Copy> 切り抜き中の多角形<参照側の特徴, 入射側の特徴> {
    pub(super) fn 空から始める() -> Self {
        Self {
            頂点: [None; 接触点の上限],
            件数: 0,
        }
    }

    pub(super) fn 頂点を1つ積む(
        &mut self,
        頂点: 多角形の頂点<参照側の特徴, 入射側の特徴>,
    ) -> Result<(), 接触点集合の問い合わせエラー> {
        let Some(置き場) = self.頂点.get_mut(self.件数) else {
            return Err(接触点集合の問い合わせエラー::受け皿の上限を越えた { 上限: 接触点の上限 });
        };
        *置き場 = Some(頂点);
        self.件数 += 1;
        Ok(())
    }

    pub(super) fn 件数(&self) -> usize {
        self.件数
    }

    pub(super) fn 番号の頂点(&self, 番号: usize) -> Option<多角形の頂点<参照側の特徴, 入射側の特徴>> {
        self.頂点.get(番号).copied().flatten()
    }
}
