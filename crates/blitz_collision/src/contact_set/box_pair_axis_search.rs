//! 2つの直方体の15本の分離軸を1本ずつ調べ、離れているかどうかと、重なっているなら最小の貫通の軸を求める工程。
//!
//! 受け取るのは2つの直方体の倍精度の幾何であり、返すのは「離れている」を表す値なしか、最小の貫通の軸である。
//! 切り抜きも接触点も作らない。作る側(`box_pair_manifold.rs`)がこの答えを受けて参照面と入射面を決める。
//!
//! 射影の基準点を第1の直方体の中心に取るのは、原点から遠い場所で射影の値が大きく育ち、区間の差を取る減算で
//! 桁が落ちることを防ぐためである。重なりは2つの区間の差だけで決まるため、基準点の取り方に依らない。
//!
//! 軸の向きを長さ1に正してから深さを比べる。正さないと、外積の軸の深さが外積の長さの倍だけ大きく出て、
//! 面の軸と比べられない。正す割り算はどの軸でも1回であり、面の軸では長さが1に近いため答えを変えない。

use crate::shape::{
    任意姿勢の直方体の倍精度の幾何, 形の局所座標の位置, 形の局所座標の変位, 直方体自身の座標軸
};

use super::box_pair_axis::直方体どうしの分離軸;
use super::cross_axis_margin::外積の軸の重なりの誤差の上界を求める;
use super::deepest_axis::{最も浅い重なりの軸だけを覚える器, 最小の貫通の軸};

pub(super) struct 直方体どうしの分離軸の走査<'幾何の寿命> {
    第1の幾何: &'幾何の寿命 任意姿勢の直方体の倍精度の幾何,
    第2の幾何: &'幾何の寿命 任意姿勢の直方体の倍精度の幾何,
    誤差の上界の尺度のメートル: f64,
}

impl<'幾何の寿命> 直方体どうしの分離軸の走査<'幾何の寿命> {
    pub(super) fn 生成する(
        第1の幾何: &'幾何の寿命 任意姿勢の直方体の倍精度の幾何,
        第2の幾何: &'幾何の寿命 任意姿勢の直方体の倍精度の幾何,
    ) -> Self {
        let 中心間の隔たりの上界 = 第1の幾何.中心().終点までの変位を求める(第2の幾何.中心()).成分の絶対値の和のメートル();
        Self {
            第1の幾何,
            第2の幾何,
            誤差の上界の尺度のメートル: 第1の幾何.半分の長さの総和のメートル()
                + 第2の幾何.半分の長さの総和のメートル()
                + 中心間の隔たりの上界,
        }
    }

    // 15本すべてで重なりが負でなければ最小の貫通の軸を返す。1本でも分離していれば値なしを返す。
    pub(super) fn 最も浅い重なりの軸を求める(&self) -> Option<最小の貫通の軸<直方体どうしの分離軸>> {
        let mut 器 = 最も浅い重なりの軸だけを覚える器::まだ何も無い状態から始める();
        for 軸 in 直方体どうしの分離軸::並べる() {
            let 向き = self.軸の向きを求める(軸);
            let 長さ = 向き.長さの二乗().sqrt();
            if 長さ.is_nan() || 長さ <= 0.0 {
                continue;
            }
            let 重なり = self
                .第1の幾何
                .基準点から見た軸への射影の区間を求める(self.基準点(), 向き)
                .相手との重なりを求める(&self.第2の幾何.基準点から見た軸への射影の区間を求める(self.基準点(), 向き));
            if 重なり.二つの形を分離しているか() {
                return None;
            }
            let 符号 = if 重なり.軸の向きを反転するか() { -1.0 } else { 1.0 };
            self.重なりを1本ぶん器へ数える(&mut 器, 軸, 重なり.重なりの深さ() / 長さ, 向き.実数倍する(符号 / 長さ), 長さ);
        }
        器.覚えている軸を取り出す()
    }

    // 1本の軸の深さを器へ渡す。面の軸は厳密な比較で、外積の軸は誤差の上界だけ厳しくして入れ替える。
    fn 重なりを1本ぶん器へ数える(
        &self,
        器: &mut 最も浅い重なりの軸だけを覚える器<直方体どうしの分離軸>,
        軸: 直方体どうしの分離軸,
        深さ: f64,
        正した向き: 形の局所座標の変位,
        外積の長さ: f64,
    ) {
        match 軸 {
            直方体どうしの分離軸::第1の直方体の面の軸(_) | 直方体どうしの分離軸::第2の直方体の面の軸(_) => {
                器.面の軸を1本数える(軸, 深さ, 正した向き);
            }
            直方体どうしの分離軸::二つの辺の向きの外積の軸 { .. } => 器.外積の軸を1本数える(
                軸,
                深さ,
                正した向き,
                外積の軸の重なりの誤差の上界を求める(self.誤差の上界の尺度のメートル, 外積の長さ),
            ),
        }
    }

    fn 基準点(&self) -> 形の局所座標の位置 {
        self.第1の幾何.中心()
    }

    // 軸の向き。面の軸は長さ1、外積の軸は2つの辺の向きのなす角の正弦の長さになる。平行な2辺では零になり、
    // 走査はその軸を飛ばす。
    fn 軸の向きを求める(&self, 軸: 直方体どうしの分離軸) -> 形の局所座標の変位 {
        match 軸 {
            直方体どうしの分離軸::第1の直方体の面の軸(軸) => self.第1の幾何.軸に沿った単位向き(軸),
            直方体どうしの分離軸::第2の直方体の面の軸(軸) => self.第2の幾何.軸に沿った単位向き(軸),
            直方体どうしの分離軸::二つの辺の向きの外積の軸 {
                第1の直方体の軸,
                第2の直方体の軸,
            } => 二つの軸の外積を求める(self.第1の幾何, 第1の直方体の軸, self.第2の幾何, 第2の直方体の軸),
        }
    }
}

fn 二つの軸の外積を求める(
    第1の幾何: &任意姿勢の直方体の倍精度の幾何,
    第1の直方体の軸: 直方体自身の座標軸,
    第2の幾何: &任意姿勢の直方体の倍精度の幾何,
    第2の直方体の軸: 直方体自身の座標軸,
) -> 形の局所座標の変位 {
    第1の幾何
        .軸に沿った単位向き(第1の直方体の軸)
        .外積(第2の幾何.軸に沿った単位向き(第2の直方体の軸))
}
