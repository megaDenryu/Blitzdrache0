//! 外積の軸へ切り替える優位幅: 接触解法へ渡す参照軸を選ぶとき、2つの辺の向きの外積で作った軸が面の軸より
//! どれだけ浅ければ参照軸を外積の軸へ切り替えてよいか、その優位の長さである。
//!
//! **これは幾何の判定ではない。** 予測した配置が与えられれば、どの分離軸の重なりが最も浅いかは幾何として
//! 決まっており、この幅はその事実を曖昧にしない。ここが決めているのは、決まっている最小の軸をそのまま参照面に
//! 使うか、それとも接触解法の安定のために面の軸を使うか、という**接触解法向けの選択の方針**である。
//! 2つの形が分離しているかどうかの判定にこの長さは入らない。
//!
//! 方針が要る理由は、参照軸が細分ごとに面の軸と外積の軸のあいだで入れ替わると、接触点集合の点の数と特徴の識別が
//! 入れ替わり、静止摩擦の錨が置き直されて島が休止できないためである(Issue #75の実測)。外積の軸が返す接触点は
//! 辺どうしの1点だけであり、1点では面で乗った箱の傾きを止められない。
//!
//! この幅を接触生成の余白と別の量にするのは、余白が運動の項を持つためである。余白は速度が上がるほど大きくなり、
//! それを軸の切り替えの幅へ丸ごと使うと、高速の対では幾何として明白に浅い外積の軸まで面の軸へ潰しうる。
//! こちらの幅は静穏とみなす運動だけから導き、運動の項を持たない。したがって速度が上がっても幅は増えない。
//! 導出は `blitz_sim` の接触の層が行い、`blitz_collision` は値の意味を知らず受け取った長さを使うだけである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11」、`crates/blitz_collision/src/contact_set/generation_margin.rs`

use super::error::接触点集合の問い合わせエラー;

/// 外積の軸が面の軸より浅くても、この長さを超えて浅くない限り参照軸を面の軸のままにする優位の長さ。
/// 0以上の有限のメートルである。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 外積の軸へ切り替える優位幅メートル {
    値: f64,
}

impl 外積の軸へ切り替える優位幅メートル {
    /// 0以上の有限値であることを確かめて作る。負の値と有限でない値は型付きエラーで拒む。
    pub fn 生成する(値: f64) -> Result<Self, 接触点集合の問い合わせエラー> {
        if !値.is_finite() || 値 < 0.0 {
            return Err(接触点集合の問い合わせエラー::外積の軸へ切り替える優位幅が負であるか有限でない);
        }
        Ok(Self { 値 })
    }

    /// 優位幅を持たない選択。幾何が決めた最小の軸をそのまま参照軸にする(丸めの上界だけは残る)。
    pub fn 優位幅を持たない() -> Self {
        Self { 値: 0.0 }
    }

    /// 面の軸を残す優位の長さであるメートル。
    pub fn 値(&self) -> f64 {
        self.値
    }

    // 外積の軸が、いま覚えている面の軸を置き換えるために必要な深さの余地。由来の違う2つの和である。
    // 1つは倍精度の丸めが作る偽の最小を退ける幾何の誤差の上界であり、もう1つはこの解法向けの優位幅である。
    pub(super) fn 丸めの上界へ足して外積の軸へ切り替える余地を求める(&self, 丸めの上界: f64) -> f64 {
        丸めの上界 + self.値
    }
}
