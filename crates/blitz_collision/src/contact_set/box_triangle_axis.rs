//! 直方体と三角形を分けうる軸の目録。直方体の面の軸が3本、三角形の面の法線が1本、直方体の3軸と三角形の
//! 3辺の外積が9本で、合わせて13本である。
//!
//! 直方体どうしの15本と数が違うのは、三角形の面の向きが1方向しかなく、辺の向きも3方向であるためである。
//! 尽きる根拠は直方体どうしと同じであり、2つの凸な形の差の面の法線がこの13方向に限られる。三角形は
//! 体積を持たない凸な形であり、表と裏で同じ法線の方向を与えるため面の軸は1本である。
//!
//! 三角形の辺の向きが直方体の軸と平行な組は数えない。外積が零になり、その組が張る面が差に存在しないため
//! である。理由は直方体どうしと同じである。
//!
//! 並びは、直方体の面・三角形の面・外積の順である。地形の三角形の上に箱が面で乗る場面では三角形の面の
//! 法線が答えになるため、三角形の面を外積より先に置く。

use crate::shape::{三角形の頂点の番号, 直方体自身の座標軸};

/// 直方体と三角形を分けうる軸のどれか1本。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 直方体と三角形の分離軸 {
    直方体の面の軸(直方体自身の座標軸),
    三角形の面の法線,
    直方体の軸と三角形の辺の外積の軸 {
        直方体の軸: 直方体自身の座標軸,
        三角形の辺の始まりの頂点: 三角形の頂点の番号,
    },
}

impl 直方体と三角形の分離軸 {
    // 13本を、直方体の面・三角形の面・外積の順に並べる。同じ深さの軸が並んだときは先に来たものが残る。
    pub(super) fn 並べる() -> [Self; 13] {
        let 箱の軸 = 直方体自身の座標軸::並べる();
        let 頂点 = 三角形の頂点の番号::並べる();
        [
            Self::直方体の面の軸(箱の軸[0]),
            Self::直方体の面の軸(箱の軸[1]),
            Self::直方体の面の軸(箱の軸[2]),
            Self::三角形の面の法線,
            Self::外積(箱の軸[0], 頂点[0]),
            Self::外積(箱の軸[0], 頂点[1]),
            Self::外積(箱の軸[0], 頂点[2]),
            Self::外積(箱の軸[1], 頂点[0]),
            Self::外積(箱の軸[1], 頂点[1]),
            Self::外積(箱の軸[1], 頂点[2]),
            Self::外積(箱の軸[2], 頂点[0]),
            Self::外積(箱の軸[2], 頂点[1]),
            Self::外積(箱の軸[2], 頂点[2]),
        ]
    }

    fn 外積(直方体の軸: 直方体自身の座標軸, 三角形の辺の始まりの頂点: 三角形の頂点の番号) -> Self {
        Self::直方体の軸と三角形の辺の外積の軸 {
            直方体の軸,
            三角形の辺の始まりの頂点,
        }
    }
}
