//! 接触生成の余白: 接触点集合を組み立てるとき、参照面の平面より外側へ出た切り抜きの角を接触解法の候補点として
//! 保つ、参照面の向きの範囲の長さである。
//!
//! **形そのものを膨らませる長さではない。** 分離軸が2つの形を分けているかどうかの判定にこの長さは入らないため、
//! 2つの形が実際に重なっていなければ接触点集合は返らない。広げているのは2つであり、どちらも重なりが決まった後の
//! 話である。1つは参照面の切り抜きが作る角のうちどこまでを候補点として残すかの範囲であり、もう1つは最も浅い軸を
//! 選ぶとき、2つの辺の向きの外積の軸が面の軸を置き換えるために必要な余地である。形を膨らませる設計にしないのは、
//! 「2つの形が重なっているか」という幾何の契約をこの余白で動かさないためである。
//!
//! 最も浅い軸の選び方にこの余白が入る理由は、この長さがその細分のあいだに2つの形の角が参照面の向きへ動きうる
//! 長さの上限、すなわち配置の分解能だからである(判断11の実装の細目)。2本の軸の深さの差がこれより小さいなら、
//! その細分の中でどちらが最小かを幾何は決めていない。決まっていないときは、接触点集合を返して傾きを止められる
//! 面の軸を採る。外積の軸は1点しか返さず、1点では箱の傾きを止められない(Issue #75、計測記録の公式値2)。
//!
//! この余白が要るのは、参照面の平面よりわずかに外に出た角を落とすと、面で乗った2つの直方体の接触点の数が配置の
//! 微小な揺れで変わるためである。塔に積んだ立方体は、非貫通の拘束が収束するほど食い込みが零へ近づくため、
//! 半分の長さ0.5メートルの箱では傾きが 食い込み ÷ 0.5 ラジアンを超えた時点で4つの角のうち2つが落ちる。
//! 落ちると残った側だけが支えることになり、箱はさらに傾き、次の細分でまた別の角が落ちる。数と特徴の識別が細分
//! ごとに入れ替わり、接触の履歴が毎回「開始」と判定する。
//!
//! 余白の内側に残した点は、離れている接触解法の候補点として負の符号付き貫通量を持って返る。非貫通の拘束は隔たりが
//! 0以上で乗数が0の点を読まないため、この点は実際に食い込むまで押し戻しを起こさない。余白を拘束の目標へ入れるのとは
//! 別のことである(前者は静置した箱が余白ぶん浮く。`_doc/設計/剛体の状態と接触.md`「判断12」が退けている)。
//!
//! 余白は形の幾何へ焼き込まず、接触生成の数値方針として問い合わせが受け取る。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断10: 凹形状と接触余白の扱い」

use super::error::接触点集合の問い合わせエラー;

/// 参照面の平面より外側へ出た切り抜きの角を候補点として保つ範囲の長さ。0以上の有限のメートルである。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 接触生成の余白メートル {
    値: f64,
}

impl 接触生成の余白メートル {
    /// 0以上の有限値であることを確かめて作る。負の値と有限でない値は型付きエラーで拒む。
    pub fn 生成する(値: f64) -> Result<Self, 接触点集合の問い合わせエラー> {
        if !値.is_finite() || 値 < 0.0 {
            return Err(接触点集合の問い合わせエラー::接触生成の余白が負であるか有限でない);
        }
        Ok(Self { 値 })
    }

    /// 余白を持たない問い合わせ。参照面の平面より外に出た角を1つも候補点にしない。
    pub fn 余白を持たない() -> Self {
        Self { 値: 0.0 }
    }

    /// 保つ範囲の長さであるメートル。
    pub fn 値(&self) -> f64 {
        self.値
    }

    // 符号付き貫通量がこの余白の内側にあるか。負の側はこの余白の長さまでを内側と数える。
    pub(super) fn 余白の内側の符号付き貫通量か(&self, 符号付き貫通量: f64) -> bool {
        符号付き貫通量 >= -self.値
    }

    // 2つの辺の向きの外積の軸が、いま覚えている面の軸を置き換えるために必要な深さの余地。倍精度の丸めが作る
    // 偽の最小を退ける上界へ、配置の分解能であるこの余白を足したものである。
    pub(super) fn 丸めの上界へ足して外積の軸の入れ替えの余地を求める(&self, 丸めの上界: f64) -> f64 {
        丸めの上界 + self.値
    }
}
