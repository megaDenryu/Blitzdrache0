//! 接触生成の余白: 接触点集合を作るとき、2つの形の表面をこの長さだけ外へ膨らませたものとして接触点を数える、
//! 数値方針の長さである。
//!
//! この余白が要るのは、参照面の切り抜きが作る角のうち、参照面の平面よりわずかに外に出た角を落とすと、
//! 面で乗った2つの直方体の接触点の数が配置の微小な揺れで変わるためである。塔に積んだ立方体は、非貫通の拘束が
//! 収束するほど食い込みが零へ近づくため、半分の長さ0.5メートルの箱では傾きが 食い込み ÷ 0.5 ラジアンを超えた
//! 時点で4つの角のうち2つが落ちる。落ちると残った側だけが支えることになり、箱はさらに傾き、次の細分でまた
//! 別の角が落ちる。数と特徴の識別が細分ごとに入れ替わり、接触の履歴が毎回「開始」と判定する。
//!
//! 余白の内側に残した点は、離れている接触点として負の符号付き貫通量を持って返る。非貫通の拘束は隔たりが0以上で
//! 乗数が0の点を読まないため、この点は実際に食い込むまで押し戻しを起こさない。余白を拘束の目標へ入れるのとは
//! 別のことである(前者は静置した箱が余白ぶん浮く。`_doc/設計/剛体の状態と接触.md`「判断12」が退けている)。
//!
//! 余白は形の幾何へ焼き込まず、接触生成の数値方針として問い合わせが受け取る。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断10: 凹形状と接触余白の扱い」

use super::error::接触点集合の問い合わせエラー;

/// 接触点集合を作るとき、形の表面を外へ膨らませて数える長さ。0以上の有限のメートルである。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 接触生成の余白メートル {
    値: f64,
}

impl 接触生成の余白メートル {
    /// 0以上の有限値であることを確かめて作る。負の値と有限でない値は型付きエラーで拒む。
    pub fn 生成する(値: f64) -> Result<Self, 接触点集合の問い合わせエラー> {
        if !値.is_finite() || 値 < 0.0 {
            return Err(接触点集合の問い合わせエラー::接触生成の余白が負であるか有限でない);
        }
        Ok(Self { 値 })
    }

    /// 余白を持たない問い合わせ。表面より外に出た点を1つも接触点にしない。
    pub fn 余白を持たない() -> Self {
        Self { 値: 0.0 }
    }

    /// 膨らませる長さであるメートル。
    pub fn 値(&self) -> f64 {
        self.値
    }

    // 符号付き貫通量がこの余白の内側にあるか。負の側はこの余白の長さまでを内側と数える。
    pub(super) fn 余白の内側の符号付き貫通量か(&self, 符号付き貫通量: f64) -> bool {
        符号付き貫通量 >= -self.値
    }
}
