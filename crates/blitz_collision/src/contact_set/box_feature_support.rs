//! 直方体の特徴を、軸ごとの側の組から組み立てる工程と、指定した向きへ最も遠い特徴を選ぶ工程。
//!
//! 特徴の型そのもの(`crate::oriented_box`の面・辺・頂点)と別のファイルへ置くのは、この組み立てが接触点集合の
//! 切り抜きのためだけに要るためである。線分の交差も掃引の接触も、軸ごとの側の組から特徴を組む必要を持たない。
//!
//! 軸ごとの側を並びの位置で受け取るのは、切り抜きが入射面の4つの頂点を「面に垂直な軸の側は固定、残る2軸の側を
//! 1つずつ変える」という決まりで数え上げるためである。辺の型は沿う軸と残る2軸の側で作るが、その2軸の並びは
//! 沿う軸から巡回で決まるため、呼び出し側が巡回の決まりを持たずに済むこの入口を置く。
//!
//! 指定した向きへ最も遠い面は、その向きと軸の内積の絶対値が最も大きい軸と、内積の符号が決める側である。
//! 絶対値が並んだときは軸の並びの先を選ぶ。同じ深さの軸が並んだときに答えを入力だけで決めるためである。

use crate::oriented_box::{直方体の辺, 直方体の面, 直方体の頂点};
use crate::shape::{
    任意姿勢の直方体の倍精度の幾何, 形の局所座標の変位, 直方体の面の向き, 直方体自身の座標軸
};

// 沿う軸と、軸の並びの順に3つ並べた側の組から辺を組む。沿う軸の位置の側は読まれない。
pub(super) fn 沿う軸と軸ごとの側から辺を組む(
    沿う軸: 直方体自身の座標軸, 軸ごとの側: [直方体の面の向き; 3]
) -> 直方体の辺 {
    直方体の辺::生成する(
        沿う軸,
        軸ごとの側[沿う軸.次の軸().並びの位置()],
        軸ごとの側[沿う軸.次の軸().次の軸().並びの位置()],
    )
}

// 2つの面が共有する辺。同じ軸に垂直な2つの面は辺を共有しないため値なしを返す。
pub(super) fn 二つの面が共有する辺を組む(面: 直方体の面, もう一方の面: 直方体の面) -> Option<直方体の辺> {
    if 面.軸() == もう一方の面.軸() {
        return None;
    }
    let mut 軸ごとの側 = [直方体の面の向き::軸の正の側; 3];
    軸ごとの側[面.軸().並びの位置()] = 面.側();
    軸ごとの側[もう一方の面.軸().並びの位置()] = もう一方の面.側();
    let 沿う軸 = 直方体自身の座標軸::並べる()
        .into_iter()
        .find(|軸| *軸 != 面.軸() && *軸 != もう一方の面.軸())?;
    Some(沿う軸と軸ごとの側から辺を組む(沿う軸, 軸ごとの側))
}

impl 任意姿勢の直方体の倍精度の幾何 {
    // 指定した向きへ最も遠い面。その面の外向きの単位法線が、向きと最も揃っている。
    pub(super) fn 向きへ最も遠い面を求める(&self, 向き: 形の局所座標の変位) -> 直方体の面 {
        let mut 最も揃った面 = 直方体の面::生成する(直方体自身の座標軸::X軸, 直方体の面の向き::軸の正の側);
        let mut 最も大きい内積の絶対値 = -1.0;
        for 軸 in 直方体自身の座標軸::並べる() {
            let 内積 = self.軸に沿った単位向き(軸).内積(向き);
            if 内積.abs() > 最も大きい内積の絶対値 {
                最も大きい内積の絶対値 = 内積.abs();
                最も揃った面 = 直方体の面::生成する(軸, 直方体の面の向き::実数の符号が指す側を求める(内積));
            }
        }
        最も揃った面
    }

    // 沿う軸を決めたうえで、指定した向きへ最も遠い辺。沿う軸以外の2軸それぞれについて、向きとの内積の符号が
    // 側を決める。
    pub(super) fn 沿う軸を決めて向きへ最も遠い辺を求める(
        &self,
        沿う軸: 直方体自身の座標軸,
        向き: 形の局所座標の変位,
    ) -> 直方体の辺 {
        let 軸ごとの側 = 直方体自身の座標軸::並べる()
            .map(|軸| 直方体の面の向き::実数の符号が指す側を求める(self.軸に沿った単位向き(軸).内積(向き)));
        沿う軸と軸ごとの側から辺を組む(沿う軸, 軸ごとの側)
    }

    // 面の上の4つの頂点。面に垂直な軸の側は固定し、残る2軸の側を輪郭の順に一巡する。隣り合う頂点は
    // 残る2軸のうち片方の側だけが違うため、この並びは面の4辺をちょうど1周する。
    pub(super) fn 面の輪郭の頂点を並べる(&self, 面: 直方体の面) -> [直方体の頂点; 4] {
        let 第1の軸 = 面.軸().次の軸();
        let 第2の軸 = 面.軸().次の軸().次の軸();
        [
            (直方体の面の向き::軸の正の側, 直方体の面の向き::軸の正の側),
            (直方体の面の向き::軸の負の側, 直方体の面の向き::軸の正の側),
            (直方体の面の向き::軸の負の側, 直方体の面の向き::軸の負の側),
            (直方体の面の向き::軸の正の側, 直方体の面の向き::軸の負の側),
        ]
        .map(|(第1の側, 第2の側)| {
            let mut 軸ごとの側 = [直方体の面の向き::軸の正の側; 3];
            軸ごとの側[面.軸().並びの位置()] = 面.側();
            軸ごとの側[第1の軸.並びの位置()] = 第1の側;
            軸ごとの側[第2の軸.並びの位置()] = 第2の側;
            直方体の頂点::軸の並びの順の側から生成する(軸ごとの側)
        })
    }
}
