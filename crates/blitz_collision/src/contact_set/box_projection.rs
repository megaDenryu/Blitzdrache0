//! 任意姿勢の直方体を1本の軸へ射影する工程。受け取るのは基準点と軸の向き、返すのはその軸の上の区間である。
//!
//! 形の表現と別のモジュールへ置くのは、この射影が分離軸の判定のためだけに要る量であり、形を焼き込む側も
//! 粗い選別の側も使わないためである。形の側が持つと、形の型が判定の都合で太る。
//!
//! 広がりは、直方体自身の3本の軸それぞれについて「軸の単位向きと射影の向きの内積の絶対値」に半分の長さを
//! 掛けて足したものである。直方体は中心について対称であるから、区間は中心の射影を挟んで両側へこの広がりだけ
//! 伸びる。軸の向きの長さが1でない場合、区間も同じ倍率で伸びる。分離軸の判定は2つの区間の差だけを見るため、
//! 長さを1に正していない向きをそのまま渡してよい。

use crate::shape::{
    任意姿勢の直方体の倍精度の幾何, 形の局所座標の位置, 形の局所座標の変位, 直方体自身の座標軸
};

use super::axis_interval::軸への射影の区間;

impl 任意姿勢の直方体の倍精度の幾何 {
    // 基準点から見て、この直方体が軸の向きの上で占める区間。
    pub(super) fn 基準点から見た軸への射影の区間を求める(
        &self,
        基準点: 形の局所座標の位置,
        軸の向き: 形の局所座標の変位,
    ) -> 軸への射影の区間 {
        let 中心の射影 = 基準点.終点までの変位を求める(self.中心()).内積(軸の向き);
        let 広がり = 直方体自身の座標軸::並べる()
            .into_iter()
            .map(|軸| self.軸に沿った単位向き(軸).内積(軸の向き).abs() * self.軸に沿った半分の長さのメートル(軸))
            .sum();
        軸への射影の区間::中心と広がりから組む(中心の射影, 広がり)
    }

    // 軸ごとの半分の長さを足し合わせた量。分離軸の重なりの誤差の上界が使う尺度の一部である。
    pub(super) fn 半分の長さの総和のメートル(&self) -> f64 {
        直方体自身の座標軸::並べる()
            .into_iter()
            .map(|軸| self.軸に沿った半分の長さのメートル(軸))
            .sum()
    }
}
