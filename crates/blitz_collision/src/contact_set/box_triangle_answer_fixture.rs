//! 直方体と三角形の問い合わせの答えを、反証が読みやすい形へ取り出す道具。問い合わせを組む工程と、重なりの答えと、
//! 重なっていることを前提にした接触点集合の取り出しを持つ。
//!
//! 反証の本体と別のファイルへ置くのは、直方体どうしの側(`box_pair_answer_fixture.rs`)と同じ理由である。
//! 同じ取り出し方を複数の反証が使うため、片方に置くともう片方が別の取り出し方を書き、期待値の読み方が2つに割れる。
//!
//! 3つの入口がどれも余白を持たない問い合わせを組むのは、接触生成の余白の効き目を見る反証を
//! `box_pair_stack_tests.rs` が別に持っており、この群の対象が参照面の入れ替わりと切り抜きの綴りだからである。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use crate::shape::{任意姿勢の直方体, 局所座標の三角形};

use super::box_triangle_feature::直方体と三角形の接触の特徴の対;
use super::box_triangle_query::{直方体と三角形の接触点集合の問い合わせ, 直方体と三角形の重なりの接触点集合};
use super::cross_axis_preference::外積の軸へ切り替える優位幅メートル;
use super::error::接触点集合の問い合わせエラー;
use super::generation_margin::接触生成の余白メートル;
use super::manifold::接触点集合;

pub(super) fn 余白なしの問い合わせを組む(
    箱: &任意姿勢の直方体,
    三角形: 局所座標の三角形,
) -> Result<直方体と三角形の接触点集合の問い合わせ, 接触点集合の問い合わせエラー> {
    直方体と三角形の接触点集合の問い合わせ::直方体と三角形と余白と優位幅から生成する(
        箱,
        三角形,
        接触生成の余白メートル::余白を持たない(),
        外積の軸へ切り替える優位幅メートル::優位幅を持たない(),
    )
}

pub(super) fn 余白なしの重なりを求める(
    箱: &任意姿勢の直方体,
    三角形: 局所座標の三角形,
) -> 直方体と三角形の重なりの接触点集合 {
    余白なしの問い合わせを組む(箱, 三角形)
        .unwrap()
        .直方体と三角形の重なりの接触点集合を求める()
        .unwrap()
}

pub(super) fn 余白なしの重なりの集合を求める(
    箱: &任意姿勢の直方体,
    三角形: 局所座標の三角形,
) -> 接触点集合<直方体と三角形の接触の特徴の対> {
    let 直方体と三角形の重なりの接触点集合::直方体と三角形が重なっている(集合) = 余白なしの重なりを求める(箱, 三角形)
    else {
        panic!("重なっているはずの直方体と三角形が離れていると答えた");
    };
    集合
}
