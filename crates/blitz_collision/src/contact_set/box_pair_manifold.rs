//! 最小の貫通の軸が決まった後に、2つの直方体の接触点を組み立てる工程。面の軸なら参照面と入射面の切り抜き、
//! 辺の向きの外積なら辺どうしの1点である。
//!
//! 参照面は、最小の貫通の軸が指す直方体の面のうち、第1の形から第2の形へ向かう向きへ最も遠いものである。
//! 入射面は相手の直方体の面のうち、その向きの逆へ最も遠いものである。参照面の外向きの単位法線と入射面の
//! 外向きの単位法線が最も向かい合う組を選ぶことで、切り抜きが最も広い重なりを拾う。
//!
//! 切り抜いた頂点のうち、参照面の平面より接触生成の余白を超えて外側に残ったものは接触点にしない。傾いて1つの辺や
//! 1つの頂点だけで触れている直方体では、この落とし方が接触点の数を2つや1つへ減らす。落とさずに残すと、触れて
//! いない角に力を掛ける接触点ができる。余白の内側で離れている頂点を残す理由は
//! `crates/blitz_collision/src/contact_set/generation_margin.rs` にある。

use crate::oriented_box::直方体で当たった特徴;
use crate::shape::任意姿勢の直方体の倍精度の幾何;

use super::box_pair_axis::直方体どうしの分離軸;
use super::box_pair_feature::直方体どうしの接触の特徴の対;
use super::contact_point::接触点;
use super::deepest_axis::最小の貫通の軸;
use super::edge_pair_contact::辺どうしの接触点を組む工程;
use super::error::接触点集合の問い合わせエラー;
use super::generation_margin::接触生成の余白メートル;
use super::manifold_builder::接触点を積む器;
use super::reference_role::参照にした側;

pub(super) struct 直方体どうしの接触点を組む工程<'幾何の寿命> {
    第1の幾何: &'幾何の寿命 任意姿勢の直方体の倍精度の幾何,
    第2の幾何: &'幾何の寿命 任意姿勢の直方体の倍精度の幾何,
    接触生成の余白: 接触生成の余白メートル,
}

impl<'幾何の寿命> 直方体どうしの接触点を組む工程<'幾何の寿命> {
    pub(super) fn 生成する(
        第1の幾何: &'幾何の寿命 任意姿勢の直方体の倍精度の幾何,
        第2の幾何: &'幾何の寿命 任意姿勢の直方体の倍精度の幾何,
        接触生成の余白: 接触生成の余白メートル,
    ) -> Self {
        Self {
            第1の幾何,
            第2の幾何,
            接触生成の余白,
        }
    }

    pub(super) fn 最小の貫通の軸から接触点を積む(
        &self,
        最小の軸: &最小の貫通の軸<直方体どうしの分離軸>,
    ) -> Result<接触点を積む器<直方体どうしの接触の特徴の対>, 接触点集合の問い合わせエラー> {
        match 最小の軸.軸() {
            直方体どうしの分離軸::第1の直方体の面の軸(_) => self.面の切り抜きで積む(最小の軸, 参照にした側::第1の形),
            直方体どうしの分離軸::第2の直方体の面の軸(_) => self.面の切り抜きで積む(最小の軸, 参照にした側::第2の形),
            直方体どうしの分離軸::二つの辺の向きの外積の軸 {
                第1の直方体の軸,
                第2の直方体の軸,
            } => {
                let mut 器 = 接触点を積む器::空から始める();
                器.接触点を1つ積む(
                    辺どうしの接触点を組む工程::生成する(self.第1の幾何, self.第2の幾何, self.接触生成の余白).接触点を組む(
                        最小の軸,
                        第1の直方体の軸,
                        第2の直方体の軸,
                    )?,
                )?;
                Ok(器)
            }
        }
    }

    // 参照面と入射面を選び、切り抜いた頂点のうち貫通しているものを接触点として積む。
    fn 面の切り抜きで積む(
        &self,
        最小の軸: &最小の貫通の軸<直方体どうしの分離軸>,
        参照にした側: 参照にした側,
    ) -> Result<接触点を積む器<直方体どうしの接触の特徴の対>, 接触点集合の問い合わせエラー> {
        let 参照面の外向き = 最小の軸
            .第1の形から第2の形へ向かう向き()
            .実数倍する(参照にした側.参照面の外向きへ揃える符号());
        let (参照の幾何, 入射の幾何) = match 参照にした側 {
            参照にした側::第1の形 => (self.第1の幾何, self.第2の幾何),
            参照にした側::第2の形 => (self.第2の幾何, self.第1の幾何),
        };
        let 枠 = 参照の幾何.面から参照の枠を組む(参照の幾何.向きへ最も遠い面を求める(参照面の外向き));
        let 入射面 = 入射の幾何.向きへ最も遠い面を求める(参照面の外向き.実数倍する(-1.0));
        let 入射の多角形 = 入射の幾何.面から入射の多角形を組む(入射面, 枠.面そのものの特徴())?;
        let 切り抜いた多角形 = 枠.入射の多角形を切り抜く(入射の多角形, 直方体で当たった特徴::直方体の面(入射面))?;
        let mut 器 = 接触点を積む器::空から始める();
        for 番号 in 0..切り抜いた多角形.件数() {
            let Some(頂点) = 切り抜いた多角形.番号の頂点(番号) else {
                continue;
            };
            let Some(貫通量) = 枠.点の符号付き貫通量を求める(頂点.位置(), self.接触生成の余白) else {
                continue;
            };
            let 参照面の上の点 = 枠.参照面の上の点を求める(頂点.位置(), 貫通量)?;
            器.接触点を1つ積む(接触点::生成する(
                参照にした側.第1の形の上の位置を選ぶ(頂点.位置(), 参照面の上の点),
                参照にした側.第2の形の上の位置を選ぶ(頂点.位置(), 参照面の上の点),
                貫通量,
                直方体どうしの接触の特徴の対::切り抜きの対から生成する(頂点.この頂点の特徴の対(), 参照にした側),
            ))?;
        }
        Ok(器)
    }
}
