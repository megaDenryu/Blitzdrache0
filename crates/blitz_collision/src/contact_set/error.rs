//! 接触点集合の問い合わせで破れる条件。
//!
//! 形そのものの破れ(中心が有限でない・半分の長さが負である等)はここに入らない。それは`直方体の生成エラー`が
//! 持ち、形を作る地点で拒まれている。ここに在るのは、重なりの判定と切り抜きが導いた値の破れである。

use blitz_math::方向エラー;
use thiserror::Error;

use crate::shape::形の局所座標の生成エラー;

/// 接触点集合の問い合わせで破れる条件。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 接触点集合の問い合わせエラー {
    /// 切り抜きが導いた接触の点を局所座標の位置として作れなかった。
    #[error("接触点集合の点を作れない: {0}")]
    接触の点を作れない(#[from] 形の局所座標の生成エラー),
    /// 求めた共有の法線を単位方向へ狭められなかった。
    #[error("接触点集合の共有の単位法線を作れない: {0}")]
    共有の単位法線を作れない(#[from] 方向エラー),
    /// 最小の貫通の軸の向きの長さが0であり、単位方向として定まらなかった。
    #[error("接触点集合の共有の単位法線が長さ0で定まらない")]
    共有の単位法線が定まらない,
    /// 参照面からの隔たりとして求めた符号付き貫通量が、接触生成の余白より外であるか有限でなかった。
    #[error("接触点集合の符号付き貫通量が接触生成の余白より外であるか有限でない")]
    貫通量が余白より外であるか有限でない,
    /// 受け取った接触生成の余白が、負であるか有限でなかった。
    #[error("接触生成の余白が負であるか有限でない")]
    接触生成の余白が負であるか有限でない,
    /// 受け取った外積の軸へ切り替える優位幅が、負であるか有限でなかった。
    #[error("外積の軸へ切り替える優位幅が負であるか有限でない")]
    外積の軸へ切り替える優位幅が負であるか有限でない,
    /// 切り抜きの途中の多角形か、積んだ接触点が受け皿の上限を越えた。
    #[error("接触点集合の受け皿の上限{上限}件を越えた")]
    受け皿の上限を越えた {
        /// 越えられた上限の件数。
        上限: usize,
    },
    /// 三角形の面積が零であり、面の向きが定まらなかった。
    #[error("接触点集合を求める三角形の面の向きが定まらない")]
    三角形の面の向きが定まらない,
}
