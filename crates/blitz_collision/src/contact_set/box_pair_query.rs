//! 直方体どうしの接触点集合の問い合わせ: 2つの任意姿勢の直方体が重なっているかを答え、重なっているなら
//! その接触点の集合を返す操作サービス。2つの直方体を倍精度で読み直してコンストラクタで保持するため、
//! 問い合わせの署名に形が現れない。
//!
//! 手順は2段である。まず15本の分離軸で重なりを調べ、1本でも分離していればそこで答える。すべてで重なって
//! いれば、最も浅い1本を選んで参照面と入射面を決め、切り抜きで接触点を作る。辺の向きの外積が最も浅ければ
//! 接触点は1つである。2つの段はそれぞれ別の長さを読む。参照軸を選ぶ段は外積の軸へ切り替える優位幅を読み、
//! 切り抜きの段は接触生成の余白を読む。由来が違う量であるため1つにまとめない(優位幅は解法向けの選択の方針、
//! 余白は運動に由来する接触継続の予測幅である)。
//!
//! 1回の問い合わせでヒープを確保しない。持つのは切り抜きの途中の多角形と接触点の受け皿だけであり、どちらも
//! 上限つきの固定の長さである。
//!
//! 共有の単位法線を単精度へ狭めるのはここ1箇所である。接触点の位置と貫通量は倍精度のまま返す。

use blitz_math::ローカル;

use crate::shape::{任意姿勢の直方体, 任意姿勢の直方体の倍精度の幾何};

use super::box_pair_axis_search::直方体どうしの分離軸の走査;
use super::box_pair_feature::直方体どうしの接触の特徴の対;
use super::box_pair_manifold::直方体どうしの接触点を組む工程;
use super::cross_axis_preference::外積の軸へ切り替える優位幅メートル;
use super::error::接触点集合の問い合わせエラー;
use super::generation_margin::接触生成の余白メートル;
use super::manifold::接触点集合;

/// 2つの直方体が重なっているかと、重なっているならその接触点集合。
///
/// 枝の大きさが釣り合わないことを承知で持つ。接触点集合が上限つきの固定の長さの配列を抱えるためであり、
/// 差を消す方法は集合をヒープへ逃がすことだが、それはこの問い合わせが確保を起こさないという要求を破る。
#[allow(clippy::large_enum_variant)]
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 二つの直方体の重なりの接触点集合 {
    /// 15本の分離軸のどれか1本が、2つの直方体を分けている。
    二つの直方体は離れている,
    /// 2つの直方体が重なっているか接しており、その接触点集合を持つ。
    二つの直方体が重なっている(接触点集合<直方体どうしの接触の特徴の対>),
}

/// 2つの任意姿勢の直方体の接触点集合の問い合わせ。2つの倍精度の幾何を保持し、重なりと接触点を答える操作サービスである。
pub struct 直方体どうしの接触点集合の問い合わせ {
    第1の幾何: 任意姿勢の直方体の倍精度の幾何,
    第2の幾何: 任意姿勢の直方体の倍精度の幾何,
    接触生成の余白: 接触生成の余白メートル,
    外積の軸へ切り替える優位幅: 外積の軸へ切り替える優位幅メートル,
}

impl 直方体どうしの接触点集合の問い合わせ {
    /// 2つの直方体を倍精度で読み直し、切り抜きが読む余白と参照軸の選択が読む優位幅と共に保持する。
    /// 読み直しは問い合わせのたびではなく、この生成の1回だけ行う。
    pub fn 二つの直方体と余白と優位幅から生成する(
        第1の直方体: &任意姿勢の直方体,
        第2の直方体: &任意姿勢の直方体,
        接触生成の余白: 接触生成の余白メートル,
        外積の軸へ切り替える優位幅: 外積の軸へ切り替える優位幅メートル,
    ) -> Self {
        Self {
            第1の幾何: 任意姿勢の直方体の倍精度の幾何::直方体から組む(第1の直方体),
            第2の幾何: 任意姿勢の直方体の倍精度の幾何::直方体から組む(第2の直方体),
            接触生成の余白,
            外積の軸へ切り替える優位幅,
        }
    }

    /// 2つの直方体の重なりと接触点集合を求める。共有の単位法線は第1の直方体から第2の直方体へ向かう。
    pub fn 二つの直方体の重なりの接触点集合を求める(
        &self,
    ) -> Result<二つの直方体の重なりの接触点集合, 接触点集合の問い合わせエラー> {
        let 走査 = 直方体どうしの分離軸の走査::生成する(&self.第1の幾何, &self.第2の幾何, self.外積の軸へ切り替える優位幅);
        let Some(最小の軸) = 走査.最も浅い重なりの軸を求める() else {
            return Ok(二つの直方体の重なりの接触点集合::二つの直方体は離れている);
        };
        let Some(正した向き) = 最小の軸.第1の形から第2の形へ向かう向き().長さで正した方向へ狭める::<ローカル>()
        else {
            return Err(接触点集合の問い合わせエラー::共有の単位法線が定まらない);
        };
        let 器 = 直方体どうしの接触点を組む工程::生成する(&self.第1の幾何, &self.第2の幾何, self.接触生成の余白)
            .最小の貫通の軸から接触点を積む(&最小の軸)?;
        Ok(二つの直方体の重なりの接触点集合::二つの直方体が重なっている(
            器.共有の単位法線を添えて集合にする(正した向き?),
        ))
    }
}
