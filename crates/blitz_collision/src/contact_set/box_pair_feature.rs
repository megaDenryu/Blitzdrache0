//! 直方体どうしの接触の特徴の対: 1つの接触点が、第1の直方体のどの特徴と第2の直方体のどの特徴の間で
//! 生まれたかである。
//!
//! 既存の`直方体で当たった特徴`を2つ組み合わせるのは、面・辺・頂点を軸と側で指す綴りが既にそこに在り、
//! 接触点集合のためにもう1つ別の綴りを作ると、同じ面が2つの名前を持つためである。
//!
//! この対が接触の追跡の綴りになる。刻みが1つ進んで形が少し動いても、面で乗り続けている接触点は同じ面と
//! 同じ頂点の対を返し、辺で切り取られた接触点は同じ2本の辺の対を返す。追跡そのもの(前の刻みの接触点集合と
//! 突き合わせて力の初期値を引き継ぐこと)は拘束の解法の担当であり、この層は綴りを返すところまでを持つ。
//!
//! 切り抜きが作る対は4種類である。入射面の頂点がそのまま残った点は「参照面と入射面の頂点」、参照面の側の
//! 平面1つで切り取られた点は「参照面の辺と入射面の辺」、2つの側の平面で切り取られて参照面の角に残った点は
//! 「参照面の頂点と入射面」、辺どうしの交差で生まれた点は「2本の辺」である。
//! どれも第1と第2のどちらが参照面であったかに依らず、この対の2つの欄へ形の順で入る。
//!
//! 全順序(`Ord`)を導出しているのは、接触の解法が刻みを跨いで接触を対応付けるとき、鍵の昇順に並べた2つの一覧を
//! 併走させるためである。値の並び自体に意味は無く、同じ入力が必ず同じ順序を与えることだけを求める。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断16: 接触の履歴は参加者の組ごとに特徴の識別を鍵に全順序の併走で対応付け、暖機はしない」

use crate::oriented_box::直方体で当たった特徴;

use super::clip_feature_pair::切り抜きの特徴の対;
use super::reference_role::参照にした側;

/// 1つの接触点が、第1の直方体のどの特徴と第2の直方体のどの特徴の間で生まれたか。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 直方体どうしの接触の特徴の対 {
    第1の直方体の特徴: 直方体で当たった特徴,
    第2の直方体の特徴: 直方体で当たった特徴,
}

impl 直方体どうしの接触の特徴の対 {
    pub(super) fn 生成する(
        第1の直方体の特徴: 直方体で当たった特徴, 第2の直方体の特徴: 直方体で当たった特徴
    ) -> Self {
        Self {
            第1の直方体の特徴,
            第2の直方体の特徴,
        }
    }

    // 切り抜きが持ち回った参照側と入射側の対を、どちらが参照であったかに従って形の順へ並べ直す。
    pub(super) fn 切り抜きの対から生成する(
        対: 切り抜きの特徴の対<直方体で当たった特徴, 直方体で当たった特徴>,
        参照にした側: 参照にした側,
    ) -> Self {
        match 参照にした側 {
            参照にした側::第1の形 => Self::生成する(対.参照側の特徴(), 対.入射側の特徴()),
            参照にした側::第2の形 => Self::生成する(対.入射側の特徴(), 対.参照側の特徴()),
        }
    }

    /// 第1の直方体の側で、この接触点を生んだ面・辺・頂点。
    pub fn 第1の直方体の特徴(&self) -> 直方体で当たった特徴 {
        self.第1の直方体の特徴
    }

    /// 第2の直方体の側で、この接触点を生んだ面・辺・頂点。
    pub fn 第2の直方体の特徴(&self) -> 直方体で当たった特徴 {
        self.第2の直方体の特徴
    }
}
