//! 接触の特徴の対に導出した全順序の試験。担当するのは、接触の解法の併走が要求する2つの性質を固定することである。
//! 1つは、綴りの違う2つの対が必ず大小で決着すること(等しいと答える組が無いこと)である。もう1つは、同じ集合を
//! どんな順で並べても整列の結果が同じ並びになることである。前者が崩れると継続する接触と新しい接触を取り違え、
//! 後者が崩れると同じ配置から作った履歴の並びが実行ごとに変わる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断16: 接触の履歴は参加者の組ごとに特徴の識別を鍵に全順序の併走で対応付け、暖機はしない」

use crate::oriented_box::{直方体で当たった特徴, 直方体の辺, 直方体の面, 直方体の頂点};
use crate::shape::{三角形の頂点の番号, 直方体の面の向き, 直方体自身の座標軸};
use crate::triangle::三角形で当たった特徴;

use super::box_pair_feature::直方体どうしの接触の特徴の対;
use super::box_triangle_feature::直方体と三角形の接触の特徴の対;

fn 直方体の特徴を全部並べる() -> Vec<直方体で当たった特徴> {
    let mut 一覧 = Vec::new();
    for 軸 in 直方体自身の座標軸::並べる() {
        for 側 in 直方体の面の向き::並べる() {
            一覧.push(直方体で当たった特徴::直方体の面(直方体の面::生成する(軸, 側)));
            for もう一方の側 in 直方体の面の向き::並べる() {
                一覧.push(直方体で当たった特徴::直方体の辺(
                    直方体の辺::生成する(軸, 側, もう一方の側),
                ));
            }
        }
    }
    for x側 in 直方体の面の向き::並べる() {
        for y側 in 直方体の面の向き::並べる() {
            for z側 in 直方体の面の向き::並べる() {
                let 頂点 = 直方体の頂点::軸の並びの順の側から生成する([x側, y側, z側]);
                一覧.push(直方体で当たった特徴::直方体の頂点(頂点));
            }
        }
    }
    一覧
}

fn 三角形の特徴を全部並べる() -> Vec<三角形で当たった特徴> {
    let mut 一覧 = vec![三角形で当たった特徴::三角形の面];
    for 番号 in 三角形の頂点の番号::並べる() {
        一覧.push(三角形で当たった特徴::三角形の辺 { 始まりの頂点: 番号 });
        一覧.push(三角形で当たった特徴::三角形の頂点(番号));
    }
    一覧
}

fn 直方体どうしの対を全部並べる() -> Vec<直方体どうしの接触の特徴の対> {
    let 特徴一覧 = 直方体の特徴を全部並べる();
    特徴一覧
        .iter()
        .flat_map(|第1| 特徴一覧.iter().map(|第2| 直方体どうしの接触の特徴の対::生成する(*第1, *第2)))
        .collect()
}

fn 直方体と三角形の対を全部並べる() -> Vec<直方体と三角形の接触の特徴の対> {
    let 三角形の特徴一覧 = 三角形の特徴を全部並べる();
    直方体の特徴を全部並べる()
        .iter()
        .flat_map(|直方体| {
            三角形の特徴一覧
                .iter()
                .map(|三角形| 直方体と三角形の接触の特徴の対::生成する(*直方体, *三角形))
        })
        .collect()
}

// 異なる2つの値が等しいと答えないこと(全順序であること)を、総当たりで確かめる。
fn 相異なる値が必ず大小で決着するか<値: Ord + Copy>(一覧: &[値]) -> bool {
    一覧
        .iter()
        .enumerate()
        .all(|(添字, 左)| 一覧[添字 + 1..].iter().all(|右| *左 < *右 || *右 < *左))
}

// 逆順に並べてから整列した結果が、素朴に整列した結果と一致するか。
fn 並べ替えても同じ並びになるか<値: Ord + Copy>(一覧: &[値]) -> bool {
    let mut 昇順 = 一覧.to_vec();
    昇順.sort();
    let mut 逆順から整列 = 一覧.to_vec();
    逆順から整列.reverse();
    逆順から整列.sort();
    昇順 == 逆順から整列
}

#[test]
fn 直方体どうしの対は全順序を持つ() {
    let 一覧 = 直方体どうしの対を全部並べる();
    assert_eq!(一覧.len(), 26 * 26);
    assert!(相異なる値が必ず大小で決着するか(&一覧));
    assert!(並べ替えても同じ並びになるか(&一覧));
}

#[test]
fn 直方体と三角形の対は全順序を持つ() {
    let 一覧 = 直方体と三角形の対を全部並べる();
    assert_eq!(一覧.len(), 26 * 7);
    assert!(相異なる値が必ず大小で決着するか(&一覧));
    assert!(並べ替えても同じ並びになるか(&一覧));
}
