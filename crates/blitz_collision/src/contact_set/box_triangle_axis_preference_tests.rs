//! 直方体と三角形でも、外積の軸が面の軸を置き換える余地に接触生成の余白が入ることの反証(Issue #75)。
//!
//! 直方体どうしの側(`box_pair_axis_preference_tests.rs`)と別に置くのは、調べる軸の目録も片側の形の射影の
//! 作り方も違い、余白を受け取る引数が在ることを型が示しても、この経路が実際に読んでいるかは別に測らないと
//! 言えないためである。
//!
//! 材料は2つである。1つ目は、箱と同じ桁の大きさ(2メートル四方。地形の升目の大きさに当たる)の地面の三角形へ、
//! 微小に傾けた立方体を沈めた配置である。2つ目は、面の軸を無条件に優先していないことの対照であり、三角形の斜辺を
//! またいで沈めた直方体である。
//!
//! 1つ目の材料では、直方体のX軸と三角形の1辺の外積の軸の深さが三角形の面の法線より3.5e-5メートルだけ浅くなる。この差は塔で導かれる
//! 余白の下限1.11e-4メートルより小さい。三角形を箱よりはるかに大きく取ると、軸を傾けたときに三角形の射影の
//! 区間が広がる量が箱の広がりを上回るため、外積の軸は最小にならない。地形の升目のように箱と同じ桁の三角形で
//! 初めてこの後退が起きる。
//! 参照: `crates/blitz_collision/src/contact_set/cross_axis_margin.rs`、`_doc/設計/剛体の状態と接触.md`「判断11」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use crate::shape::局所座標の三角形;

use super::box_triangle_query::{直方体と三角形の接触点集合の問い合わせ, 直方体と三角形の重なりの接触点集合};
use super::generation_margin::接触生成の余白メートル;
use super::query_fixture::{三角形を作る, 回転なし, 直方体を作る, 軸まわりの回転};

const 半分の長さ: f32 = 0.5;
const 食い込み: f32 = 0.001;
// 塔の静穏な対で導かれる接触生成の余白の下限であるメートル(計測記録の公式値11)。
const 塔の余白の下限: f64 = 1.11e-4;
// Z軸まわりに5e-4ラジアン傾ける角度である度。
const 傾きの度: f32 = -0.028_647_89;

// 箱と同じ桁の大きさの地面の三角形。頂点の並びが決める面に垂直な向きは真下である。
fn 升目ほどの大きさの地面の三角形() -> 局所座標の三角形 {
    三角形を作る([[-1.0, 0.0, -1.0], [1.0, 0.0, -1.0], [-1.0, 0.0, 1.0]])
}

// 地面の三角形へ食い込みのぶんだけ沈め、微小に傾けて水平にずらした直方体の接触点の数。
fn 微小に傾けて三角形へ沈めた直方体の接触点の数(余白: 接触生成の余白メートル) -> usize {
    let 箱 = 直方体を作る(
        [0.02, 半分の長さ - 食い込み, 0.05],
        軸まわりの回転([0.0, 0.0, 1.0], 傾きの度),
        [半分の長さ; 3],
    );
    let 問い合わせ = 直方体と三角形の接触点集合の問い合わせ::直方体と三角形と余白から生成する(
        &箱,
        升目ほどの大きさの地面の三角形(),
        余白,
    )
    .unwrap();
    let 直方体と三角形の重なりの接触点集合::直方体と三角形が重なっている(集合) = 問い合わせ.直方体と三角形の重なりの接触点集合を求める().unwrap()
    else {
        panic!("重なっているはずの直方体と三角形が離れていると答えた");
    };
    集合.件数()
}

#[test]
fn 微小に傾けて三角形へ沈めた直方体は余白の内側の差では三角形の面の軸を参照面にする() {
    let 余白 = 接触生成の余白メートル::生成する(塔の余白の下限).unwrap();
    let 件数 = 微小に傾けて三角形へ沈めた直方体の接触点の数(余白);
    assert!(件数 >= 3, "三角形の面の軸が選ばれていれば3点以上になる(実測{件数}点)");
}

#[test]
fn 余白を持たない同じ配置では外積の軸が選ばれて接触点が一点になる() {
    let 件数 = 微小に傾けて三角形へ沈めた直方体の接触点の数(接触生成の余白メートル::余白を持たない());
    assert_eq!(件数, 1, "余白を外した反証で接触点が1つに落ちていない(実測{件数}点)");
}

// 三角形の斜辺をまたいで沈めた直方体。三角形と重なるのは角の小さな断片だけであり、直方体の面の軸と三角形の面の
// 法線の深さが半分の長さそのもの(0.5メートル)であるのに対し、直方体のY軸と斜辺の外積の軸の深さはその断片の
// 幅(0.0707メートル)である。差が余白を桁で超えるため、余白があっても外積の軸が選ばれる。
fn 三角形の斜辺をまたいで沈めた直方体の接触点の数(余白: 接触生成の余白メートル) -> usize {
    let 箱 = 直方体を作る([0.45, 0.0, 0.45], 回転なし(), [半分の長さ; 3]);
    let 問い合わせ = 直方体と三角形の接触点集合の問い合わせ::直方体と三角形と余白から生成する(
        &箱,
        升目ほどの大きさの地面の三角形(),
        余白,
    )
    .unwrap();
    let 直方体と三角形の重なりの接触点集合::直方体と三角形が重なっている(集合) = 問い合わせ.直方体と三角形の重なりの接触点集合を求める().unwrap()
    else {
        panic!("重なっているはずの直方体と三角形が離れていると答えた");
    };
    集合.件数()
}

#[test]
fn 三角形の斜辺をまたいで沈めた直方体では余白があっても外積の軸が選ばれる() {
    let 余白 = 接触生成の余白メートル::生成する(塔の余白の下限).unwrap();
    let 件数 = 三角形の斜辺をまたいで沈めた直方体の接触点の数(余白);
    assert_eq!(件数, 1, "辺どうしの交差で接触点が1つでない(実測{件数}点)");
}
