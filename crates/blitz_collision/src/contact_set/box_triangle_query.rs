//! 直方体と三角形の接触点集合の問い合わせ: 任意姿勢の直方体と1枚の三角形が重なっているかを答え、
//! 重なっているならその接触点の集合を返す操作サービス。直方体を倍精度で読み直し、三角形の面の向きを求めて
//! コンストラクタで保持するため、問い合わせの署名に形が現れない。
//!
//! 手順は直方体どうしと同じ2段である。まず13本の分離軸で重なりを調べ、1本でも分離していればそこで答える。
//! すべてで重なっていれば、最も浅い1本を選んで参照面と入射面を決め、切り抜きで接触点を作る。接触生成の余白は
//! 直方体どうしと同じく両方の段で読まれる。
//!
//! 共有の単位法線は直方体から三角形へ向かう。地形の上に箱が乗る場面では、この向きが下向き(箱から地表へ
//! 向かう向き)になる。箱を押し上げる向きはこの逆であり、向きの意味付けは受け取る側が行う。
//!
//! 面積が零の三角形は問い合わせを組めない。面の向きが定まらず、分離軸の目録の1本が作れないためである。

use blitz_math::ローカル;

use crate::shape::{
    任意姿勢の直方体, 任意姿勢の直方体の倍精度の幾何, 局所座標の三角形, 面の向きを備えた三角形
};

use super::box_triangle_axis_search::直方体と三角形の分離軸の走査;
use super::box_triangle_feature::直方体と三角形の接触の特徴の対;
use super::box_triangle_manifold::直方体と三角形の接触点を組む工程;
use super::error::接触点集合の問い合わせエラー;
use super::generation_margin::接触生成の余白メートル;
use super::manifold::接触点集合;

/// 直方体と三角形が重なっているかと、重なっているならその接触点集合。
///
/// 枝の大きさが釣り合わない理由は直方体どうしの答えと同じである
/// (`crates/blitz_collision/src/contact_set/box_pair_query.rs`)。
#[allow(clippy::large_enum_variant)]
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 直方体と三角形の重なりの接触点集合 {
    /// 13本の分離軸のどれか1本が、直方体と三角形を分けている。
    直方体と三角形は離れている,
    /// 直方体と三角形が重なっているか接しており、その接触点集合を持つ。
    直方体と三角形が重なっている(接触点集合<直方体と三角形の接触の特徴の対>),
}

/// 任意姿勢の直方体と1枚の三角形の接触点集合の問い合わせ。倍精度の幾何と面の向きを備えた三角形を保持する操作サービスである。
pub struct 直方体と三角形の接触点集合の問い合わせ {
    直方体の幾何: 任意姿勢の直方体の倍精度の幾何,
    三角形: 面の向きを備えた三角形,
    接触生成の余白: 接触生成の余白メートル,
}

impl 直方体と三角形の接触点集合の問い合わせ {
    /// 直方体を倍精度で読み直し、三角形の面の向きを求めて保持する。面積が零の三角形は型付きエラーで拒む。
    pub fn 直方体と三角形と余白から生成する(
        直方体: &任意姿勢の直方体,
        三角形: 局所座標の三角形,
        接触生成の余白: 接触生成の余白メートル,
    ) -> Result<Self, 接触点集合の問い合わせエラー> {
        let Some(面の向きを備えた) = 面の向きを備えた三角形::三角形から生成する(三角形) else {
            return Err(接触点集合の問い合わせエラー::三角形の面の向きが定まらない);
        };
        Ok(Self {
            直方体の幾何: 任意姿勢の直方体の倍精度の幾何::直方体から組む(直方体),
            三角形: 面の向きを備えた,
            接触生成の余白,
        })
    }

    /// 直方体と三角形の重なりと接触点集合を求める。共有の単位法線は直方体から三角形へ向かう。
    pub fn 直方体と三角形の重なりの接触点集合を求める(
        &self,
    ) -> Result<直方体と三角形の重なりの接触点集合, 接触点集合の問い合わせエラー> {
        let Some(走査) = 直方体と三角形の分離軸の走査::生成する(&self.直方体の幾何, &self.三角形, self.接触生成の余白)
        else {
            return Err(接触点集合の問い合わせエラー::三角形の面の向きが定まらない);
        };
        let Some(最小の軸) = 走査.最も浅い重なりの軸を求める() else {
            return Ok(直方体と三角形の重なりの接触点集合::直方体と三角形は離れている);
        };
        let Some(正した向き) = 最小の軸.第1の形から第2の形へ向かう向き().長さで正した方向へ狭める::<ローカル>()
        else {
            return Err(接触点集合の問い合わせエラー::共有の単位法線が定まらない);
        };
        let 器 = 直方体と三角形の接触点を組む工程::生成する(走査.直方体の幾何(), 走査.三角形(), self.接触生成の余白)
            .最小の貫通の軸から接触点を積む(&最小の軸)?;
        Ok(
            直方体と三角形の重なりの接触点集合::直方体と三角形が重なっている(
                器.共有の単位法線を添えて集合にする(正した向き?),
            ),
        )
    }
}
