//! 接触点集合の反証が共有する材料。直方体と三角形を組む道具、答えを読む道具、そして分離軸の答え合わせに使う
//! 独立した重なりの判定を持つ。
//!
//! 独立した重なりの判定を反証の側に置くのは、分離軸の完全性を分離軸そのもので確かめても何も言えないためで
//! ある。判定は線分と直方体の交差(`crate::oriented_box`)だけを使う。2つの凸多面体が重なることは、
//! 「一方の頂点が他方の中に在る」か「一方の辺が他方を貫く」かのどちらかと同じである。交わりの多面体の
//! どの頂点も3枚の面の交点であり、3枚が片方の形から来るなら頂点が相手の中に在り、2枚と1枚に分かれるなら
//! 辺が相手の面を貫いているからである。線分の交差の判定は分離軸を1本も使わない別の数学(3本の軸への射影と
//! 区間の交差)で書かれているため、答え合わせとして独立している。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{クォータニオン, メートル, ローカル, 位置};

use crate::oriented_box::{直方体の線分の問い合わせ, 直方体の辺, 線分が直方体に最初に当たる点};
use crate::shape::{
    任意姿勢の直方体, 任意姿勢の直方体の倍精度の幾何, 局所座標の三角形, 形の局所座標の位置, 形を貫く線分, 直方体の軸ごとの半分の長さ,
    直方体の面の向き, 直方体自身の座標軸,
};

pub(super) fn 回転なし() -> クォータニオン<ローカル, ローカル> {
    クォータニオン::生成する(0.0, 0.0, 0.0, 1.0).unwrap()
}

// 指定した軸まわりの回転。角度は度で受ける。
pub(super) fn 軸まわりの回転(軸: [f32; 3], 度: f32) -> クォータニオン<ローカル, ローカル> {
    let 半角 = 度.to_radians() / 2.0;
    let 長さ = (軸[0] * 軸[0] + 軸[1] * 軸[1] + 軸[2] * 軸[2]).sqrt();
    let 正弦 = 半角.sin() / 長さ;
    クォータニオン::生成する(軸[0] * 正弦, 軸[1] * 正弦, 軸[2] * 正弦, 半角.cos()).unwrap()
}

pub(super) fn 直方体を作る(
    中心: [f32; 3], 回転: クォータニオン<ローカル, ローカル>, 半分: [f32; 3]
) -> 任意姿勢の直方体 {
    let 中心の位置 = 位置::生成する(メートル::生成する(中心[0]), メートル::生成する(中心[1]), メートル::生成する(中心[2]));
    let 半分の長さ = 直方体の軸ごとの半分の長さ::生成する(半分.map(メートル::生成する)).unwrap();
    任意姿勢の直方体::生成する(中心の位置, 回転, 半分の長さ).unwrap()
}

pub(super) fn 局所の点(成分: [f64; 3]) -> 形の局所座標の位置 {
    形の局所座標の位置::生成する(成分[0], 成分[1], 成分[2]).unwrap()
}

pub(super) fn 三角形を作る(頂点: [[f64; 3]; 3]) -> 局所座標の三角形 {
    局所座標の三角形::三つの頂点から生成する(頂点.map(局所の点))
}

pub(super) fn 位置の成分(位置: 形の局所座標の位置) -> [f64; 3] {
    [位置.xのメートル(), 位置.yのメートル(), 位置.zのメートル()]
}

// 2つの直方体が重なっているか(接しているだけの状態を含まない)を、線分と直方体の交差だけで判定する。
pub(super) fn 線分の交差だけで重なりを判定する(第1: &任意姿勢の直方体, 第2: &任意姿勢の直方体) -> bool {
    一方の辺が他方を貫くか(第1, 第2) || 一方の辺が他方を貫くか(第2, 第1)
}

fn 一方の辺が他方を貫くか(辺を出す側: &任意姿勢の直方体, 貫かれる側: &任意姿勢の直方体) -> bool {
    let 幾何 = 任意姿勢の直方体の倍精度の幾何::直方体から組む(辺を出す側);
    let 問い合わせ = 直方体の線分の問い合わせ::直方体から生成する(貫かれる側);
    for 沿う軸 in 直方体自身の座標軸::並べる() {
        for 第1の側 in 直方体の面の向き::並べる() {
            for 第2の側 in 直方体の面の向き::並べる() {
                let 辺 = 直方体の辺::生成する(沿う軸, 第1の側, 第2の側);
                let 始点 = 幾何.辺の始点の位置を求める(辺);
                let 終点 = 始点.検査済みの変位だけ進んだ位置を求める(幾何.辺の変位を求める(辺));
                let 線分 = 形を貫く線分::生成する(始点, 終点);
                if let Ok(線分が直方体に最初に当たる点::直方体に当たる(_)) = 問い合わせ.線分が直方体に最初に当たる点を求める(&線分)
                {
                    return true;
                }
            }
        }
    }
    false
}
