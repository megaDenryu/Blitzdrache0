//! 切り抜きの途中で持ち回る特徴の対。参照面の側の特徴と、入射面の側の特徴を1つに束ねる。
//!
//! 形の種類ごとの対(`直方体どうしの接触の特徴の対`など)と別の型にするのは、切り抜きが「どちらが第1の形か」
//! を知らないためである。切り抜きが知っているのは参照面と入射面の役だけであり、形の順へ並べ直すのは
//! 役を割り当てた側の仕事である。裸の2つ組で持ち回すと、どちらが参照側かを署名が語らなくなる。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 切り抜きの特徴の対<参照側の特徴, 入射側の特徴> {
    参照側の特徴: 参照側の特徴,
    入射側の特徴: 入射側の特徴,
}

impl<参照側の特徴: Copy, 入射側の特徴: Copy> 切り抜きの特徴の対<参照側の特徴, 入射側の特徴> {
    pub(super) fn 生成する(参照側の特徴: 参照側の特徴, 入射側の特徴: 入射側の特徴) -> Self {
        Self {
            参照側の特徴, 入射側の特徴
        }
    }

    pub(super) fn 参照側の特徴(&self) -> 参照側の特徴 {
        self.参照側の特徴
    }

    pub(super) fn 入射側の特徴(&self) -> 入射側の特徴 {
        self.入射側の特徴
    }
}
