//! 接触点集合: 重なった2つの形が触れ合う点をまとめて持ち、全部の点で共有する単位法線を1つ添えたものである。
//!
//! 法線を点ごとに持たせず集合が1つ持つのは、この集合が最小の貫通の1本の軸から作られており、どの点も同じ
//! 押し戻す向きを共有するためである。点ごとに持たせると、同じ値の写しが最大8つできて食い違いを作れる。
//!
//! 向きは第1の形から第2の形へ向かう。第2の形をこの向きへ貫通量だけ動かすと、その接触点は触れ合うだけの
//! 状態になる。どちらを第1の形として渡したかを、受け取る側は知っている必要がある。
//!
//! 点の並びは入力だけで決まる。切り抜きが入射面の頂点を辿る順が固定であり、辺どうしの接触は1点だからである。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断14: 決定性の維持」

use blitz_math::{ローカル, 方向};

use super::contact_point::接触点;
use super::manifold_capacity::接触点の上限;

/// 重なった2つの形が触れ合う点の集合。全部の点が共有する、第1の形から第2の形へ向かう単位法線を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触点集合<特徴の識別: Copy> {
    共有の単位法線: 方向<ローカル>,
    接触点: [Option<接触点<特徴の識別>>; 接触点の上限],
    件数: usize,
}

impl<特徴の識別: Copy> 接触点集合<特徴の識別> {
    pub(super) fn 生成する(
        共有の単位法線: 方向<ローカル>, 接触点: [Option<接触点<特徴の識別>>; 接触点の上限], 件数: usize
    ) -> Self {
        Self {
            共有の単位法線,
            接触点,
            件数,
        }
    }

    /// 全部の接触点が共有する、第1の形から第2の形へ向かう単位法線。
    pub fn 共有の単位法線(&self) -> 方向<ローカル> {
        self.共有の単位法線
    }

    /// 持っている接触点の件数。上限は`接触点の上限`である。
    pub fn 件数(&self) -> usize {
        self.件数
    }

    /// 接触点を、切り抜きが入射面の頂点を辿った順に並べる。並びは入力だけで決まる。
    pub fn 接触点を順に並べる(&self) -> impl Iterator<Item = &接触点<特徴の識別>> {
        self.接触点[..self.件数].iter().flatten()
    }
}
