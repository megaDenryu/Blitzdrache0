//! 直方体と三角形の接触点集合で、接触生成の余白が参照面の外へ出た角を保つことの反証。
//!
//! 直方体どうしの側(`box_pair_stack_tests.rs`)と別に置くのは、参照面が三角形の面である経路が、直方体の面を
//! 参照面にする経路と別の切り抜きの工程を通るためである。余白を受け取る引数が両方の経路に在ることは型が示すが、
//! 三角形の側の切り抜きが余白を実際に読んでいることは、この経路で測らないと言えない。
//!
//! 傾きの境目は直方体どうしと同じ幾何で決まる。半分の長さ0.5メートルの直方体では、傾き θ が底面の角を
//! 0.5 sin θ だけ持ち上げるため、余白を持たない問い合わせは sin θ が 食い込み ÷ 0.5 を超えた時点で
//! 4つのうち2つを落とし、余白のある問い合わせは (食い込み + 余白) ÷ 0.5 を超えるまで落とさない。
//! 参照: `crates/blitz_collision/src/contact_set/generation_margin.rs`

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use crate::shape::局所座標の三角形;

use super::box_triangle_query::{直方体と三角形の接触点集合の問い合わせ, 直方体と三角形の重なりの接触点集合};
use super::cross_axis_preference::外積の軸へ切り替える優位幅メートル;
use super::generation_margin::接触生成の余白メートル;
use super::query_fixture::{三角形を作る, 直方体を作る, 軸まわりの回転};

const 半分の長さ: f32 = 0.5;
const 食い込み: f32 = 0.001;
const 塔の余白: f64 = 0.005;

// 高さ0の平面に置いた大きな三角形。頂点の並びが決める面に垂直な向きは真下である。
fn 大きな地面の三角形() -> 局所座標の三角形 {
    三角形を作る([[-10.0, 0.0, -10.0], [10.0, 0.0, -10.0], [0.0, 0.0, 10.0]])
}

// 地面の三角形へ食い込みのぶんだけ沈めた直方体を置き、鉛直面内で傾けたときの接触点の数。
fn 三角形へ沈めた直方体の接触点の数(傾きの度: f32, 余白: 接触生成の余白メートル) -> usize {
    let 箱 = 直方体を作る(
        [0.0, 半分の長さ - 食い込み, 0.0],
        軸まわりの回転([0.0, 0.0, 1.0], 傾きの度),
        [半分の長さ; 3],
    );
    let 問い合わせ = 直方体と三角形の接触点集合の問い合わせ::直方体と三角形と余白と優位幅から生成する(
        &箱,
        大きな地面の三角形(),
        余白,
        外積の軸へ切り替える優位幅メートル::優位幅を持たない(),
    )
    .unwrap();
    let 直方体と三角形の重なりの接触点集合::直方体と三角形が重なっている(集合) = 問い合わせ.直方体と三角形の重なりの接触点集合を求める().unwrap()
    else {
        panic!("重なっているはずの直方体と三角形が離れていると答えた");
    };
    集合.件数()
}

#[test]
fn 三角形の上で微小に傾いた直方体は余白のある問い合わせで4つの接触点を保つ() {
    let 余白 = 接触生成の余白メートル::生成する(塔の余白).unwrap();
    for 傾きの度 in [0.15_f32, 0.3, 0.6] {
        assert_eq!(
            三角形へ沈めた直方体の接触点の数(傾きの度, 余白),
            4,
            "傾き{傾きの度}度で余白のある問い合わせが4つの接触点を保たなかった"
        );
    }
}

#[test]
fn 余白を外すと同じ傾きで接触点が2つへ減る() {
    let 余白なし = 接触生成の余白メートル::余白を持たない();
    for 傾きの度 in [0.15_f32, 0.3, 0.6] {
        assert_eq!(
            三角形へ沈めた直方体の接触点の数(傾きの度, 余白なし),
            2,
            "傾き{傾きの度}度で余白を外した反証が2つの接触点へ減らなかった"
        );
    }
}

#[test]
fn 余白より外へ出る傾きでは余白があっても接触点が2つへ減る() {
    let 余白 = 接触生成の余白メートル::生成する(塔の余白).unwrap();
    for 傾きの度 in [1.0_f32, 3.0] {
        assert_eq!(
            三角形へ沈めた直方体の接触点の数(傾きの度, 余白),
            2,
            "傾き{傾きの度}度で余白のある問い合わせが2つの接触点へ減らなかった"
        );
    }
}
