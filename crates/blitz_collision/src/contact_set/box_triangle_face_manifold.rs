//! 直方体と三角形が面で触れているときに、参照面の切り抜きから接触点を積む工程。参照面が直方体になる場合と
//! 三角形になる場合の2つを持つ。
//!
//! 辺どうしの1点を組む工程(`box_triangle_edge_contact.rs`)と同じく、軸の種類から組み立て方を選ぶ側とは別の
//! 型にしてある。直方体どうしの側が1つの手順で済むのに対しこちらが2つ要るのは、参照面と入射面の特徴の型が
//! 枝ごとに入れ替わり、1つの手順へまとめられないためである。
//!
//! 地形の三角形の上に箱が乗る場面では三角形を参照面にした切り抜きが走る。入射面は箱の面のうち三角形へ最も
//! 向かい合うものであり、切り抜きの結果は三角形の内側に収まる箱の面の輪郭になる。逆に三角形が箱の足元へ
//! 収まる場面では、直方体を参照面にした切り抜きが三角形の頂点をそのまま残す。

use crate::oriented_box::直方体で当たった特徴;
use crate::shape::{任意姿勢の直方体の倍精度の幾何, 形の局所座標の変位, 面の向きを備えた三角形};
use crate::triangle::三角形で当たった特徴;

use super::box_triangle_feature::直方体と三角形の接触の特徴の対;
use super::error::接触点集合の問い合わせエラー;
use super::generation_margin::接触生成の余白メートル;
use super::manifold_builder::接触点を積む器;
use super::reference_frame::参照の面の枠;
use super::reference_role::参照にした側;
use super::solver_candidate_point::接触解法の候補点;

pub(super) struct 直方体と三角形の面の切り抜きの工程<'形の寿命> {
    直方体の幾何: &'形の寿命 任意姿勢の直方体の倍精度の幾何,
    三角形: &'形の寿命 面の向きを備えた三角形,
    接触生成の余白: 接触生成の余白メートル,
}

impl<'形の寿命> 直方体と三角形の面の切り抜きの工程<'形の寿命> {
    pub(super) fn 生成する(
        直方体の幾何: &'形の寿命 任意姿勢の直方体の倍精度の幾何,
        三角形: &'形の寿命 面の向きを備えた三角形,
        接触生成の余白: 接触生成の余白メートル,
    ) -> Self {
        Self {
            直方体の幾何,
            三角形,
            接触生成の余白,
        }
    }

    // 直方体の面を参照にして三角形を切り抜く。
    pub(super) fn 直方体を参照にして積む(
        &self,
        直方体から三角形へ向かう向き: 形の局所座標の変位,
    ) -> Result<接触点を積む器<直方体と三角形の接触の特徴の対>, 接触点集合の問い合わせエラー> {
        let 枠 = self
            .直方体の幾何
            .面から参照の枠を組む(self.直方体の幾何.向きへ最も遠い面を求める(直方体から三角形へ向かう向き));
        let 入射の多角形 = self.三角形.入射の多角形を組む(枠.面そのものの特徴())?;
        let 切り抜いた多角形 = 枠.入射の多角形を切り抜く(入射の多角形, 三角形で当たった特徴::三角形の面)?;
        let mut 器 = 接触点を積む器::空から始める();
        for 番号 in 0..切り抜いた多角形.件数() {
            let Some(頂点) = 切り抜いた多角形.番号の頂点(番号) else {
                continue;
            };
            let Some(貫通量) = 枠.点の符号付き貫通量を求める(頂点.位置(), self.接触生成の余白) else {
                continue;
            };
            器.接触解法の候補点を1つ積む(接触解法の候補点::生成する(
                枠.参照面の上の点を求める(頂点.位置(), 貫通量)?,
                頂点.位置(),
                貫通量,
                直方体と三角形の接触の特徴の対::直方体を参照にした切り抜きの対から生成する(
                    頂点.この頂点の特徴の対(),
                ),
            ))?;
        }
        Ok(器)
    }

    // 三角形を参照にして直方体の面を切り抜く。参照面の外向きは直方体の側を向くため、向きを反転する。
    pub(super) fn 三角形を参照にして積む(
        &self,
        直方体から三角形へ向かう向き: 形の局所座標の変位,
    ) -> Result<接触点を積む器<直方体と三角形の接触の特徴の対>, 接触点集合の問い合わせエラー> {
        let 参照面の外向き = 直方体から三角形へ向かう向き.実数倍する(参照にした側::第2の形.参照面の外向きへ揃える符号());
        let 枠: 参照の面の枠<三角形で当たった特徴> = self.三角形.参照の枠を組む(参照面の外向き);
        let 入射面 = self.直方体の幾何.向きへ最も遠い面を求める(参照面の外向き.実数倍する(-1.0));
        let 入射の多角形 = self.直方体の幾何.面から入射の多角形を組む(入射面, 枠.面そのものの特徴())?;
        let 切り抜いた多角形 = 枠.入射の多角形を切り抜く(入射の多角形, 直方体で当たった特徴::直方体の面(入射面))?;
        let mut 器 = 接触点を積む器::空から始める();
        for 番号 in 0..切り抜いた多角形.件数() {
            let Some(頂点) = 切り抜いた多角形.番号の頂点(番号) else {
                continue;
            };
            let Some(貫通量) = 枠.点の符号付き貫通量を求める(頂点.位置(), self.接触生成の余白) else {
                continue;
            };
            器.接触解法の候補点を1つ積む(接触解法の候補点::生成する(
                頂点.位置(),
                枠.参照面の上の点を求める(頂点.位置(), 貫通量)?,
                貫通量,
                直方体と三角形の接触の特徴の対::三角形を参照にした切り抜きの対から生成する(
                    頂点.この頂点の特徴の対(),
                ),
            ))?;
        }
        Ok(器)
    }
}
