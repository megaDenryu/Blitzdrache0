//! 三角形から、切り抜きの部品(参照の面の枠と入射の多角形)を組む工程。
//!
//! 直方体の側と別のファイルへ置くのは、側の平面の作り方が違うためである。直方体の側の平面は隣り合う面の
//! 外向きの単位法線を反転するだけで得られるが、三角形には隣り合う面が無く、面に垂直な変位と辺の変位の
//! 外積で内向きの法線を組む。
//!
//! 内向きの法線を「面に垂直な変位と辺の変位の外積」に取ると、三角形の内側を向く。頂点の並びが決める面に
//! 垂直な変位を天頂に見立てると、辺の変位を天頂まわりに4分の1回転させた向きが三角形の内側を指すためである。
//! 長さは1に正していない。切り抜きが符号と比だけを使うためである。
//!
//! 参照の面の枠が持つ面の外向きの単位法線は、入射面の側を向く。三角形の表と裏のどちらが入射面の側かは
//! 分離軸の走査が決めるため、呼び出し側が向きを渡す。三角形自身は表裏を持たない
//! (`_doc/設計/世界の形と衝突基盤.md`「判断10: 衝突形状が宣言できる属性」)。

use crate::shape::{三角形の頂点の番号, 形の局所座標の変位, 面の向きを備えた三角形};
use crate::triangle::三角形で当たった特徴;

use super::clip_feature_pair::切り抜きの特徴の対;
use super::clip_plane::参照面の側の平面;
use super::clip_polygon::{切り抜き中の多角形, 多角形の頂点};
use super::error::接触点集合の問い合わせエラー;
use super::reference_frame::参照の面の枠;

impl 面の向きを備えた三角形 {
    // 三角形を参照の面の枠へ写す。外向きの単位法線は入射面の側を向くものを呼び出し側から受け取る。
    pub(super) fn 参照の枠を組む(
        &self, 面の外向きの単位法線: 形の局所座標の変位
    ) -> 参照の面の枠<三角形で当たった特徴> {
        let mut 側の平面 = [None; 4];
        let mut 件数 = 0;
        for 番号 in 三角形の頂点の番号::並べる() {
            側の平面[件数] = Some(参照面の側の平面::生成する(
                self.頂点の位置(番号),
                self.面に垂直な変位().外積(self.辺の変位を求める(番号)),
                番号,
            ));
            件数 += 1;
        }
        参照の面の枠::生成する(
            self.頂点の位置(三角形の頂点の番号::第1の頂点),
            面の外向きの単位法線,
            三角形で当たった特徴::三角形の面,
            側の平面,
            件数,
        )
    }

    // 三角形を入射の多角形へ写す。頂点の特徴はその頂点、辺の特徴はその頂点から次の頂点へ張る辺である。
    pub(super) fn 入射の多角形を組む<参照側の特徴: Copy>(
        &self,
        参照面そのものの特徴: 参照側の特徴,
    ) -> Result<切り抜き中の多角形<参照側の特徴, 三角形で当たった特徴>, 接触点集合の問い合わせエラー> {
        let mut 多角形 = 切り抜き中の多角形::空から始める();
        for 番号 in 三角形の頂点の番号::並べる() {
            多角形.頂点を1つ積む(多角形の頂点::生成する(
                self.頂点の位置(番号),
                切り抜きの特徴の対::生成する(参照面そのものの特徴, 三角形で当たった特徴::三角形の頂点(番号)),
                切り抜きの特徴の対::生成する(参照面そのものの特徴, 三角形で当たった特徴::三角形の辺 { 始まりの頂点: 番号 }),
            ))?;
        }
        Ok(多角形)
    }
}
