//! 1つの接触点集合が持てる接触点の上限と、その根拠。
//!
//! 上限を定数で持つのは、接触点を積む受け皿を固定の長さの配列にしてヒープの確保を起こさないためである。
//! 定数を切り抜きの側と受け皿の側で別々に書くと、片方だけを増やした食い違いが桁あふれとして出る。
//!
//! 根拠は切り抜きの点数の上界である。凸な多角形を1つの半平面で切り抜いた結果は、もとの頂点数をnとして
//! 高々n+1個の頂点を持つ。切り抜きは高々1本の辺を2つに割り、外へ出た頂点を落とすためである。参照面が
//! 直方体の面なら側の平面は4つ、三角形なら3つであり、入射面が直方体の面なら頂点は4つ、三角形なら3つである。
//! 組み合わせは3つあり、直方体の面を直方体の面で切り抜く場合が4から4回増えて8、三角形を直方体の面で
//! 切り抜く場合が3から4回増えて7、直方体の面を三角形で切り抜く場合が4から3回増えて7である。したがって
//! どの組み合わせでも8を越えない。
//!
//! 辺と辺が交差して1点だけを返す場合も同じ受け皿を使う。1は8を越えない。
//!
//! 貫通していない点(参照面の平面より外側に残った点)は接触点にしないため、実際の件数はこの上界より小さくなる。
//! 上界を件数の期待値として使ってはならない。

/// 1つの接触点集合が持てる接触点の上限。切り抜きが作る頂点数の上界である。
pub const 接触点の上限: usize = 8;
