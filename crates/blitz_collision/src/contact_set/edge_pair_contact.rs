//! 最小の貫通の軸が2つの直方体の辺の向きの外積であるときの、1点だけの接触点を組む工程。
//!
//! この場合の接触は、2つの直方体の辺どうしが交差する1点である。面で乗る接触と違って切り抜きを通さないのは、
//! 交わっているのが2つの線分であり、切り取る輪郭が無いためである。
//!
//! 接触に関わる辺は、軸の向きへ最も遠い辺である。第1の直方体では第1から第2へ向かう向きへ、第2の直方体では
//! その逆向きへ取る。沿う軸は分離軸が指す2本の軸である。
//!
//! 貫通量は軸の上で測った重なりの深さである。2つの点の隔たりから求め直さないのは、隔たりが軸に垂直な成分を
//! 含みうるためであり、この層が答えるのは軸に沿った食い込みだからである。

use crate::oriented_box::直方体で当たった特徴;
use crate::shape::{任意姿勢の直方体の倍精度の幾何, 直方体自身の座標軸};

use super::box_pair_feature::直方体どうしの接触の特徴の対;
use super::deepest_axis::最小の貫通の軸;
use super::error::接触点集合の問い合わせエラー;
use super::generation_margin::接触生成の余白メートル;
use super::penetration_depth::符号付き貫通量メートル;
use super::segment_pair_point::二つの線分の最近接の点;
use super::solver_candidate_point::接触解法の候補点;

pub(super) struct 辺どうしの接触点を組む工程<'幾何の寿命> {
    第1の幾何: &'幾何の寿命 任意姿勢の直方体の倍精度の幾何,
    第2の幾何: &'幾何の寿命 任意姿勢の直方体の倍精度の幾何,
    接触生成の余白: 接触生成の余白メートル,
}

impl<'幾何の寿命> 辺どうしの接触点を組む工程<'幾何の寿命> {
    pub(super) fn 生成する(
        第1の幾何: &'幾何の寿命 任意姿勢の直方体の倍精度の幾何,
        第2の幾何: &'幾何の寿命 任意姿勢の直方体の倍精度の幾何,
        接触生成の余白: 接触生成の余白メートル,
    ) -> Self {
        Self {
            第1の幾何,
            第2の幾何,
            接触生成の余白,
        }
    }

    pub(super) fn 接触点を組む<軸: Copy>(
        &self,
        最小の軸: &最小の貫通の軸<軸>,
        第1の直方体の沿う軸: 直方体自身の座標軸,
        第2の直方体の沿う軸: 直方体自身の座標軸,
    ) -> Result<接触解法の候補点<直方体どうしの接触の特徴の対>, 接触点集合の問い合わせエラー> {
        let 向き = 最小の軸.第1の形から第2の形へ向かう向き();
        let 第1の辺 = self.第1の幾何.沿う軸を決めて向きへ最も遠い辺を求める(第1の直方体の沿う軸, 向き);
        let 第2の辺 = self
            .第2の幾何
            .沿う軸を決めて向きへ最も遠い辺を求める(第2の直方体の沿う軸, 向き.実数倍する(-1.0));
        let 最近接 = 二つの線分の最近接の点::二本の線分から求める(
            self.第1の幾何.辺の始点の位置を求める(第1の辺),
            self.第1の幾何.辺の変位を求める(第1の辺),
            self.第2の幾何.辺の始点の位置を求める(第2の辺),
            self.第2の幾何.辺の変位を求める(第2の辺),
        );
        Ok(接触解法の候補点::生成する(
            最近接.第1の線分の上の点(),
            最近接.第2の線分の上の点(),
            符号付き貫通量メートル::余白の内側であることを確かめて生成する(
                最小の軸.重なりの深さのメートル(),
                self.接触生成の余白,
            )?,
            直方体どうしの接触の特徴の対::生成する(
                直方体で当たった特徴::直方体の辺(第1の辺),
                直方体で当たった特徴::直方体の辺(第2の辺),
            ),
        ))
    }
}
