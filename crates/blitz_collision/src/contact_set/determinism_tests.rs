//! 決定性と対称性の反証。同じ入力を2回問い合わせると同じ集合が同じ順で出ることと、2つの直方体を入れ替えると
//! 単位法線の符号だけが反転して接触点が対応することを見る。
//!
//! 入れ替えたときに接触点の並びまで同じであることは要求しない。参照面に選ばれる形が入れ替えで変わりうるため、
//! 切り抜きが輪郭を辿る順も変わるからである。要求するのは、点の集まりが順序を除いて一致することである。

#![allow(clippy::unwrap_used)]

use crate::contact_set::box_pair_query::{二つの直方体の重なりの接触点集合, 直方体どうしの接触点集合の問い合わせ};
use crate::shape::任意姿勢の直方体;

use super::box_pair_answer_fixture::床を作る;
use super::query_fixture::{位置の成分, 回転なし, 直方体を作る, 軸まわりの回転};

// 接触点1つを、第1の形の上の点・第2の形の上の点・貫通量の7つの量を百万分の1メートルまで書いた綴りへ落とし、
// 並べ替えて比べられる形にする。実数のまま並べ替えないのは、順序の全順序性を綴りの側で保証するためである。
fn 接触点の並びを整列して取り出す(第1: &任意姿勢の直方体, 第2: &任意姿勢の直方体) -> Vec<[String; 7]> {
    let 問い合わせ = 直方体どうしの接触点集合の問い合わせ::二つの直方体から生成する(第1, 第2);
    let 二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) = 問い合わせ.二つの直方体の重なりの接触点集合を求める().unwrap()
    else {
        panic!("重なっているはずの直方体が離れていると答えた");
    };
    let mut 並び: Vec<[String; 7]> = 集合
        .接触点を順に並べる()
        .map(|点| {
            let 第1の側 = 位置の成分(点.第1の形の上の位置());
            let 第2の側 = 位置の成分(点.第2の形の上の位置());
            [
                百万分の1メートルまでの綴り(第1の側[0]),
                百万分の1メートルまでの綴り(第1の側[1]),
                百万分の1メートルまでの綴り(第1の側[2]),
                百万分の1メートルまでの綴り(第2の側[0]),
                百万分の1メートルまでの綴り(第2の側[1]),
                百万分の1メートルまでの綴り(第2の側[2]),
                百万分の1メートルまでの綴り(点.貫通量().値()),
            ]
        })
        .collect();
    並び.sort_unstable();
    並び
}

fn 百万分の1メートルまでの綴り(値: f64) -> String {
    let 零の符号を揃えた = if 値 == 0.0 { 0.0 } else { 値 };
    format!("{零の符号を揃えた:.6}")
}

#[test]
fn 同じ入力を2回問い合わせると同じ接触点集合が同じ順で出る() {
    let 床 = 床を作る();
    let 箱 = 直方体を作る([0.3, 1.2, -0.7], 軸まわりの回転([1.0, 2.0, 3.0], 37.0), [1.0, 1.0, 1.0]);
    let 問い合わせ = 直方体どうしの接触点集合の問い合わせ::二つの直方体から生成する(&箱, &床);
    let 一度目の答え = 問い合わせ.二つの直方体の重なりの接触点集合を求める().unwrap();
    let 二度目の答え = 問い合わせ.二つの直方体の重なりの接触点集合を求める().unwrap();
    assert_eq!(一度目の答え, 二度目の答え, "同じ入力の2回の問い合わせが違う接触点集合を返した");
}

#[test]
fn 二つの直方体を入れ替えると単位法線の符号だけが反転する() {
    let 床 = 床を作る();
    let 箱 = 直方体を作る([0.0, 0.9, 0.0], 回転なし(), [1.0, 1.0, 1.0]);
    let 順方向 = 直方体どうしの接触点集合の問い合わせ::二つの直方体から生成する(&箱, &床);
    let 逆方向 = 直方体どうしの接触点集合の問い合わせ::二つの直方体から生成する(&床, &箱);
    let (二つの直方体の重なりの接触点集合::二つの直方体が重なっている(順), 二つの直方体の重なりの接触点集合::二つの直方体が重なっている(逆)) = (
        順方向.二つの直方体の重なりの接触点集合を求める().unwrap(),
        逆方向.二つの直方体の重なりの接触点集合を求める().unwrap(),
    ) else {
        panic!("重なっているはずの直方体が離れていると答えた");
    };
    assert_eq!(順.件数(), 逆.件数(), "入れ替えで接触点の数が変わった");
    for (順の成分, 逆の成分) in [
        (順.共有の単位法線().x(), 逆.共有の単位法線().x()),
        (順.共有の単位法線().y(), 逆.共有の単位法線().y()),
        (順.共有の単位法線().z(), 逆.共有の単位法線().z()),
    ] {
        assert!((順の成分 + 逆の成分).abs() < 1e-6, "入れ替えで単位法線の符号だけが反転していない");
    }
}

#[test]
fn 二つの直方体を入れ替えても接触点の組が順序を除いて一致する() {
    let 床 = 床を作る();
    let 箱 = 直方体を作る([0.0, 0.9, 0.0], 回転なし(), [1.0, 1.0, 1.0]);
    let 順 = 接触点の並びを整列して取り出す(&箱, &床);
    let 逆 = 接触点の並びを整列して取り出す(&床, &箱);
    let mut 入れ替えた: Vec<[String; 7]> = 逆
        .into_iter()
        .map(|組| {
            let [第1のx, 第1のy, 第1のz, 第2のx, 第2のy, 第2のz, 量] = 組;
            [第2のx, 第2のy, 第2のz, 第1のx, 第1のy, 第1のz, 量]
        })
        .collect();
    入れ替えた.sort_unstable();
    assert_eq!(順, 入れ替えた, "入れ替えた問い合わせの接触点が順序を除いて一致しない");
}
