//! 木を辿って出した答えが、階層を使わない総当たりの答えと一致することの反証。覆いの問い合わせと対の列挙の
//! 両方を見る。
//!
//! 木の辿り方の誤りは、答えが少なくなる形(交わる節点を捨てる)でも多くなる形(交わらない節点を下る)でも出る。
//! 総当たりと集合ごと突き合わせることで、どちらの向きの誤りも1つの反証で捕まえる。
//!
//! 覆いは、形が密に並ぶ範囲の中と外の両方を通るように無作為に選ぶ。範囲の外の覆いだけを見ると、答えが空の
//! ままで一致し、辿り方の誤りが隠れる。

#![allow(clippy::unwrap_used)]

use super::index::動く形の空間索引;
use super::margin::箱に持たせるゆとりの幅;
use super::sample_fixture::{中心と半分の長さから箱を組む, 動く形の見本};
use crate::pseudo_random_fixture::決まった種から進む擬似乱数;

fn 既定の幅の索引() -> 動く形の空間索引 {
    動く形の空間索引::ゆとりの幅から生成する(箱に持たせるゆとりの幅::人型と家具の大きさに見合う既定の幅())
}

#[test]
fn 覆いの問い合わせが総当たりと一致する() {
    let 見本 = 動く形の見本::無作為な箱から作る(300, 21);
    let mut 索引 = 既定の幅の索引();
    見本.索引へ登録する(&mut 索引);
    let mut 乱数 = 決まった種から進む擬似乱数::種から始める(22);
    let mut 受け皿 = Vec::new();
    let mut 挙がった総件数 = 0;
    for _ in 0..400 {
        let 中心 = [0usize, 1, 2].map(|_| 乱数.範囲の中の値(-70.0, 70.0));
        let 半分の長さ = [0usize, 1, 2].map(|_| 乱数.範囲の中の値(0.1, 12.0));
        let 覆い = 中心と半分の長さから箱を組む(中心, 半分の長さ);
        索引.覆いに触れうる形の識別子を集める(&覆い, &mut 受け皿).unwrap();
        assert_eq!(
            受け皿,
            見本.覆いに触れうる識別子を総当たりで求める(&索引, &覆い),
            "覆い{中心:?}で答えが食い違う"
        );
        挙がった総件数 += 受け皿.len();
    }
    assert!(挙がった総件数 > 0, "どの覆いも候補を挙げておらず、この反証が何も見ていない");
}

#[test]
fn 対の列挙が総当たりと一致する() {
    let 見本 = 動く形の見本::無作為な箱から作る(200, 23);
    let mut 索引 = 既定の幅の索引();
    見本.索引へ登録する(&mut 索引);
    let mut 受け皿 = Vec::new();
    索引.重なりうる形の対を集める(&mut 受け皿).unwrap();
    let 総当たり = 見本.重なりうる対を総当たりで求める(&索引);
    assert!(!総当たり.is_empty(), "見本に重なる対が1つも無く、反証が何も見ていない");
    assert_eq!(受け皿, 総当たり);
}

#[test]
fn 形を出し入れした後でも総当たりと一致する() {
    let 見本 = 動く形の見本::無作為な箱から作る(250, 24);
    let mut 索引 = 既定の幅の索引();
    見本.索引へ登録する(&mut 索引);
    for (順番, (識別子, 実体の箱)) in 見本.一覧().iter().enumerate() {
        if 順番 % 5 == 0 {
            索引.形を1つ除去する(*識別子).unwrap();
            索引.形を1つ登録する(*識別子, 実体の箱).unwrap();
        }
    }
    let mut 受け皿 = Vec::new();
    索引.重なりうる形の対を集める(&mut 受け皿).unwrap();
    assert_eq!(受け皿, 見本.重なりうる対を総当たりで求める(&索引));
}
