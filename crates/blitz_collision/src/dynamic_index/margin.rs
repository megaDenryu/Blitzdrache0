//! 箱に持たせるゆとりの幅: 実体の箱を全方向へ広げてから木へ載せる幅である。
//!
//! この幅が索引の性格を決める。広げた箱の中に実体が居る間、箱の更新は木を1節点も触らない。幅を大きく取るほど
//! 木を組み替える回数は減るが、覆いに触れうると答える形が増え、詳細判定へ渡る当たらない候補が増える。幅を
//! 小さく取ると逆になり、極端に0へ寄せると、形が1ミリ動くたびに葉を外して挿し直すことになる。
//!
//! 既定を0.1メートルに置く根拠は、この索引が最初に相手にする物体の1刻みの移動である。ゲームの更新は1フレーム
//! 60分の1秒の固定の刻みで進む(`crates/blitz_app/src/game/step_seconds.rs`)。人が走る速さである秒速6メートル
//! では1刻みの移動が0.1メートルであり、幅を0.1メートルに取ると、まっすぐ走り続ける物体はおよそ2刻みに1回だけ
//! 木を触ることになる。挿し直した直後の箱は実体の外側を0.1メートル包んでおり、1刻み進んだ先の実体はまだその中に
//! 収まり、2刻み進んだ先で初めてはみ出すためである。人型の当たり判定の半径がおよそ0.3メートル、すなわち実体の箱の
//! 一辺が0.6メートルであるから、両側へ0.1メートルずつ広げた箱の一辺は0.8メートルであり、一辺で1.33倍の広がりに
//! なる。当たらない候補が桁で増えることはない。この値は実測で選んだものではなく、実測するまでの出発点である。
//! 覆いの問い合わせ1回あたりの候補数を測った日に、測った値で選び直す。
//!
//! 幅は利用者が生成のときに決めて索引が保持し、問い合わせや更新の署名には現れない。索引ごとに違う幅を選べる
//! ようにするのは、キャラクターの索引と破壊片の索引で1刻みの移動が桁で違うためである。
//!
//! 上限を形状の座標の絶対値の上限と同じ2の24乗メートルに置くのは、幅そのものが端を桁あふれさせる大きさに
//! ならないようにするためである。
//!
//! 注意: この上限は、広げた箱の端が有限であることまでは保証しない。端の大きさを決めるのは大域の座標であり、
//! そちらに上限は無いためである。両端の絶対値が倍精度の最大の桁に近い実体の箱では、幅がいくら小さくても
//! 広げた端が無限大になる。木へ載せる直前に広げた箱の端を確かめるのは索引の側である。
//! 参照: `crates/blitz_collision/src/dynamic_index/box_edge_check.rs`

use blitz_math::メートル;

use crate::shape::形状の座標の絶対値の上限メートル;

use super::error::箱に持たせるゆとりの幅の生成エラー;

// 既定として選ぶ幅であるメートル。根拠はこのファイルの冒頭にある。
const 既定のゆとりの幅のメートル: f32 = 0.1;

/// 実体の箱を全方向へ広げてから木へ載せる幅。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 箱に持たせるゆとりの幅(メートル);

impl 箱に持たせるゆとりの幅 {
    /// 幅から作る。0以下の幅と、有限でない幅と、形状の座標の上限を越えた幅を拒む。0を拒むのは、ゆとりが0の索引が
    /// 形の微小な移動のたびに木を組み替え、この索引を選ぶ理由そのものを失うためである。
    pub fn 生成する(幅: メートル) -> Result<Self, 箱に持たせるゆとりの幅の生成エラー> {
        if !幅.値().is_finite() {
            return Err(箱に持たせるゆとりの幅の生成エラー::幅が有限でない);
        }
        if 幅.値() <= 0.0 {
            return Err(箱に持たせるゆとりの幅の生成エラー::幅が0以下);
        }
        if 幅.値() > 形状の座標の絶対値の上限メートル {
            return Err(箱に持たせるゆとりの幅の生成エラー::幅が上限を越えている);
        }
        Ok(Self(幅))
    }

    /// 人型のキャラクターと家具の大きさの剛体に見合う既定の幅。0.1メートルである。
    pub fn 人型と家具の大きさに見合う既定の幅() -> Self {
        Self(メートル::生成する(既定のゆとりの幅のメートル))
    }

    /// 実体の箱を広げる幅。
    pub fn 幅(&self) -> メートル {
        self.0
    }
}
