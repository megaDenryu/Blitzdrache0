//! 反証が共有する見本の材料。箱を組む道具と、無作為な箱を持つ形の集まり、およびその集まりを索引へ載せる操作を持つ。
//!
//! 見本の集まりが実体の箱を自分で持つのは、総当たりの答えを索引の中を見ずに組むためである。索引が答えを間違えて
//! いても、見本の側の答えはその誤りに影響されない。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{大域メートル, 大域ワールド位置};

use crate::shape::大域の軸平行の直方体;

use super::identifier::動く形の識別子;
use super::index::動く形の空間索引;
use super::pseudo_random_fixture::決まった種から進む擬似乱数;

// 無作為な箱の中心が入る範囲であるメートル。
const 中心の範囲メートル: f64 = 50.0;
// 無作為な箱の軸ごとの半分の長さが入る範囲であるメートル。
const 半分の長さの下限メートル: f64 = 0.25;
const 半分の長さの上限メートル: f64 = 3.0;

pub(super) fn 位置を組む(成分: [f64; 3]) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(成分[0]),
        大域メートル::生成する(成分[1]),
        大域メートル::生成する(成分[2]),
    )
}

pub(super) fn 端の成分から箱を組む(最小: [f64; 3], 最大: [f64; 3]) -> 大域の軸平行の直方体 {
    大域の軸平行の直方体::二点に外接する箱を求める(位置を組む(最小), 位置を組む(最大))
}

pub(super) fn 中心と半分の長さから箱を組む(中心: [f64; 3], 半分の長さ: [f64; 3]) -> 大域の軸平行の直方体 {
    端の成分から箱を組む(
        [0usize, 1, 2].map(|軸| 中心[軸] - 半分の長さ[軸]),
        [0usize, 1, 2].map(|軸| 中心[軸] + 半分の長さ[軸]),
    )
}

pub(super) struct 動く形の見本 {
    形ごとの実体の箱: Vec<(動く形の識別子, 大域の軸平行の直方体)>,
}

impl 動く形の見本 {
    pub(super) fn 無作為な箱から作る(件数: u64, 種: u64) -> Self {
        let mut 乱数 = 決まった種から進む擬似乱数::種から始める(種);
        let 形ごとの実体の箱 = (0..件数)
            .map(|番号| {
                let 中心 = [0usize, 1, 2].map(|_| 乱数.範囲の中の値(-中心の範囲メートル, 中心の範囲メートル));
                let 半分の長さ = [0usize, 1, 2].map(|_| 乱数.範囲の中の値(半分の長さの下限メートル, 半分の長さの上限メートル));
                (動く形の識別子::番号から生成する(番号), 中心と半分の長さから箱を組む(中心, 半分の長さ))
            })
            .collect();
        Self { 形ごとの実体の箱 }
    }

    pub(super) fn 一覧(&self) -> &[(動く形の識別子, 大域の軸平行の直方体)] {
        &self.形ごとの実体の箱
    }

    pub(super) fn 索引へ登録する(&self, 索引: &mut 動く形の空間索引) {
        for (識別子, 実体の箱) in &self.形ごとの実体の箱 {
            索引.形を1つ登録する(*識別子, 実体の箱).unwrap();
        }
    }
}
