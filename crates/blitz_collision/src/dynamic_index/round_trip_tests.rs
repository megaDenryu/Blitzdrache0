//! 登録と除去と更新の往復の反証。載せた形が問い合わせに出てくること、外した形が出てこないこと、動かした形が
//! 新しい場所で出てきて古い場所から消えることを見る。
//!
//! あわせて、登録されていない識別子への操作と、二重の登録と、端の壊れた箱が、どれも型付きエラーで返ることを見る。
//! 黙って何もしない実装では、呼び出し側の台帳と索引の食い違いが問い合わせの答えとしてしか現れない。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::error::動く形の空間索引の操作エラー;
use super::identifier::動く形の識別子;
use super::index::動く形の空間索引;
use super::margin::箱に持たせるゆとりの幅;
use super::sample_fixture::{中心と半分の長さから箱を組む, 端の成分から箱を組む};
use super::update_result::箱の更新で木を組み替えたか;

fn 既定の幅の索引() -> 動く形の空間索引 {
    動く形の空間索引::ゆとりの幅から生成する(箱に持たせるゆとりの幅::人型と家具の大きさに見合う既定の幅())
}

fn 覆いに出る識別子(索引: &動く形の空間索引, 中心: [f64; 3]) -> Vec<動く形の識別子> {
    let mut 受け皿 = Vec::new();
    索引
        .覆いに触れうる形の識別子を集める(&中心と半分の長さから箱を組む(中心, [0.01, 0.01, 0.01]), &mut 受け皿)
        .unwrap();
    受け皿
}

#[test]
fn 登録した形は覆いに出て除去すると出なくなる() {
    let 識別子 = 動く形の識別子::番号から生成する(7);
    let mut 索引 = 既定の幅の索引();
    索引
        .形を1つ登録する(識別子, &中心と半分の長さから箱を組む([3.0, 0.0, 0.0], [1.0, 1.0, 1.0]))
        .unwrap();
    assert_eq!(覆いに出る識別子(&索引, [3.0, 0.0, 0.0]), vec![識別子]);
    assert!(索引.登録されているか(識別子));
    索引.形を1つ除去する(識別子).unwrap();
    assert_eq!(覆いに出る識別子(&索引, [3.0, 0.0, 0.0]), Vec::new());
    assert_eq!(索引.登録件数(), 0);
}

#[test]
fn 箱を動かすと新しい場所に出て古い場所から消える() {
    let 識別子 = 動く形の識別子::番号から生成する(1);
    let mut 索引 = 既定の幅の索引();
    索引
        .形を1つ登録する(識別子, &中心と半分の長さから箱を組む([0.0, 0.0, 0.0], [1.0, 1.0, 1.0]))
        .unwrap();
    let 結果 = 索引
        .形の箱を更新する(識別子, &中心と半分の長さから箱を組む([40.0, 0.0, 0.0], [1.0, 1.0, 1.0]))
        .unwrap();
    assert_eq!(結果, 箱の更新で木を組み替えたか::葉を挿し直した);
    assert_eq!(覆いに出る識別子(&索引, [40.0, 0.0, 0.0]), vec![識別子]);
    assert_eq!(覆いに出る識別子(&索引, [0.0, 0.0, 0.0]), Vec::new());
}

#[test]
fn 登録されていない識別子への操作は型付きエラーで返る() {
    let 識別子 = 動く形の識別子::番号から生成する(99);
    let mut 索引 = 既定の幅の索引();
    let 箱 = 中心と半分の長さから箱を組む([0.0, 0.0, 0.0], [1.0, 1.0, 1.0]);
    let 除去の誤り = 索引.形を1つ除去する(識別子).unwrap_err();
    assert_eq!(除去の誤り, 動く形の空間索引の操作エラー::識別子が登録されていない { 識別子 });
    let 更新の誤り = 索引.形の箱を更新する(識別子, &箱).unwrap_err();
    assert_eq!(更新の誤り, 動く形の空間索引の操作エラー::識別子が登録されていない { 識別子 });
    索引.形を1つ登録する(識別子, &箱).unwrap();
    let 二重の誤り = 索引.形を1つ登録する(識別子, &箱).unwrap_err();
    assert_eq!(二重の誤り, 動く形の空間索引の操作エラー::識別子が既に登録されている { 識別子 });
}

#[test]
fn 端の壊れた箱の登録は型付きエラーで返る() {
    let mut 索引 = 既定の幅の索引();
    let 有限でない箱 = 端の成分から箱を組む([0.0, 0.0, 0.0], [f64::INFINITY, 1.0, 1.0]);
    let 誤り = 索引.形を1つ登録する(動く形の識別子::番号から生成する(1), &有限でない箱).unwrap_err();
    assert_eq!(誤り, 動く形の空間索引の操作エラー::実体の箱の端が有限でない);
    let 裏返った箱 = 中心と半分の長さから箱を組む([0.0, 0.0, 0.0], [1.0, 1.0, 1.0]).全方向へ広げた箱を求める(メートル::生成する(-10.0));
    let 裏返りの誤り = 索引.形を1つ登録する(動く形の識別子::番号から生成する(2), &裏返った箱).unwrap_err();
    assert_eq!(裏返りの誤り, 動く形の空間索引の操作エラー::実体の箱の最小が最大を越えている);
    assert_eq!(索引.登録件数(), 0);
}
