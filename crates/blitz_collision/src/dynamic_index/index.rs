//! 動く形の空間索引の本体: 木とゆとりの幅と、識別子ごとの葉の対応表を保持し、形の登録・除去・箱の更新に答える。
//!
//! ゆとりの幅をコンストラクタで受け取って保持するため、登録と更新の署名に幅が現れない。同じ索引の中で形ごとに
//! 違う幅を使う経路が無くなり、ゆとりの中に居るかの判定と、載せる箱の作り方が食い違わない。
//!
//! 対応表を並びの決まった木で持つのは、重なりうる対の列挙が識別子の昇順で形を辿るためと、同じ操作列から同じ
//! 順序で辿れるためである。走査のたびに並べ直す表では、同じ集合でも辿る順が実行ごとに変わりうる。
//!
//! 前提: 実体の箱を渡すのは利用者であり、形が動いたら箱を更新するのも利用者である。索引は、載せた箱が今の形を
//! 包んでいるかを自分では確かめられない。更新を怠った形は、覆いに触れているのに候補へ挙がらない。

use std::collections::BTreeMap;

use crate::shape::大域の軸平行の直方体;

use super::error::動く形の空間索引の操作エラー;
use super::identifier::動く形の識別子;
use super::margin::箱に持たせるゆとりの幅;
use super::node::動く形の木の節点の位置;
use super::tree::動く形の境界箱の木;
use super::update_result::箱の更新で木を組み替えたか;

/// 動く物体の外接する箱を保持し、覆いに触れうる形と重なりうる形の対を挙げる空間索引。
pub struct 動く形の空間索引 {
    木: 動く形の境界箱の木,
    識別子ごとの葉: BTreeMap<動く形の識別子, 動く形の木の節点の位置>,
    ゆとりの幅: 箱に持たせるゆとりの幅,
}

impl 動く形の空間索引 {
    /// ゆとりの幅を受け取って、形が1つも登録されていない索引を作る。
    pub fn ゆとりの幅から生成する(ゆとりの幅: 箱に持たせるゆとりの幅) -> Self {
        Self {
            木: 動く形の境界箱の木::空の木から始める(),
            識別子ごとの葉: BTreeMap::new(),
            ゆとりの幅,
        }
    }

    /// 実体の箱を持つ形を1つ登録する。木へ載せるのは、実体の箱をゆとりの幅だけ全方向へ広げた箱である。
    pub fn 形を1つ登録する(
        &mut self,
        識別子: 動く形の識別子,
        実体の箱: &大域の軸平行の直方体,
    ) -> Result<(), 動く形の空間索引の操作エラー> {
        実体の箱が端を組める値であることを確かめる(実体の箱)?;
        if self.識別子ごとの葉.contains_key(&識別子) {
            return Err(動く形の空間索引の操作エラー::識別子が既に登録されている { 識別子 });
        }
        let 位置 = self.木.葉を1枚挿す(識別子, self.ゆとり付きの箱を求める(実体の箱));
        self.識別子ごとの葉.insert(識別子, 位置);
        Ok(())
    }

    /// 登録済みの形を1つ除去する。登録されていない識別子は型付きエラーで返す。
    pub fn 形を1つ除去する(&mut self, 識別子: 動く形の識別子) -> Result<(), 動く形の空間索引の操作エラー> {
        let Some(位置) = self.識別子ごとの葉.remove(&識別子) else {
            return Err(動く形の空間索引の操作エラー::識別子が登録されていない { 識別子 });
        };
        self.木.葉を1枚外す(位置);
        Ok(())
    }

    /// 登録済みの形の実体の箱を更新する。今のゆとり付きの箱が新しい実体の箱を丸ごと含むなら木を触らず、
    /// はみ出たときだけ葉を外して挿し直す。
    pub fn 形の箱を更新する(
        &mut self,
        識別子: 動く形の識別子,
        実体の箱: &大域の軸平行の直方体,
    ) -> Result<箱の更新で木を組み替えたか, 動く形の空間索引の操作エラー> {
        実体の箱が端を組める値であることを確かめる(実体の箱)?;
        let Some(位置) = self.識別子ごとの葉.get(&識別子).copied() else {
            return Err(動く形の空間索引の操作エラー::識別子が登録されていない { 識別子 });
        };
        if self.木.節点を読む(位置).境界().相手を丸ごと含むか(実体の箱) {
            return Ok(箱の更新で木を組み替えたか::構造を触らなかった);
        }
        self.木.葉を1枚外す(位置);
        let 挿し直した位置 = self.木.葉を1枚挿す(識別子, self.ゆとり付きの箱を求める(実体の箱));
        self.識別子ごとの葉.insert(識別子, 挿し直した位置);
        Ok(箱の更新で木を組み替えたか::葉を挿し直した)
    }

    /// 登録されている形の数。
    pub fn 登録件数(&self) -> usize {
        self.識別子ごとの葉.len()
    }

    /// その識別子の形が登録されているか。
    pub fn 登録されているか(&self, 識別子: 動く形の識別子) -> bool {
        self.識別子ごとの葉.contains_key(&識別子)
    }

    // 実体の箱をゆとりの幅だけ全方向へ広げた箱。広げる操作は端を外向きへ丸めるため、広げた箱は実体の箱を必ず含む。
    pub(super) fn ゆとり付きの箱を求める(&self, 実体の箱: &大域の軸平行の直方体) -> 大域の軸平行の直方体 {
        実体の箱.全方向へ広げた箱を求める(self.ゆとりの幅.幅())
    }

    pub(super) fn 木(&self) -> &動く形の境界箱の木 {
        &self.木
    }

    pub(super) fn 識別子ごとの葉(&self) -> &BTreeMap<動く形の識別子, 動く形の木の節点の位置> {
        &self.識別子ごとの葉
    }
}

// 箱の端が有限で、最小の端が最大の端を越えていないことを確かめる。有限でない端を載せると、木がどの覆いとも
// 交わらない箱、あるいはどの覆いとも交わる箱を静かに持つ。
fn 実体の箱が端を組める値であることを確かめる(
    箱: &大域の軸平行の直方体,
) -> Result<(), 動く形の空間索引の操作エラー> {
    let 最小 = 箱.最小の端();
    let 最大 = 箱.最大の端();
    let 端の成分 = [最小.x(), 最小.y(), 最小.z(), 最大.x(), 最大.y(), 最大.z()];
    if 端の成分.into_iter().any(|成分| !成分.値().is_finite()) {
        return Err(動く形の空間索引の操作エラー::実体の箱の端が有限でない);
    }
    if [最小.x(), 最小.y(), 最小.z()]
        .into_iter()
        .zip([最大.x(), 最大.y(), 最大.z()])
        .any(|(最小の成分, 最大の成分)| 最小の成分.値() > 最大の成分.値())
    {
        return Err(動く形の空間索引の操作エラー::実体の箱の最小が最大を越えている);
    }
    Ok(())
}
