//! 動く形の識別子: 索引の利用者が動く形1つへ与える番号である。
//!
//! 索引が番号を発行して返す形にしないのは、利用者(剛体・キャラクター・破壊片)が自分の台帳で物体を指す綴りを既に
//! 持っており、発行された番号を持たせると同じ物体を指す綴りが2つになるためである。索引は受け取った番号を保持し、
//! 列挙でそのまま返す。番号と利用者の台帳の対応は利用者が持つ。
//!
//! 全順序を持たせるのは、列挙の並びをこの順に固定するためである。木の形は登録と除去の順で変わるが、答えの並びを
//! 識別子の昇順にすれば、同じ集合を答えるどの木も同じ並びを返す。木の形に依らない並びは、決定性の主張を
//! 「同じ操作列なら同じ答え」より強い「同じ集合なら同じ並び」にする。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断14: 決定性の維持」

/// 索引の利用者が動く形1つへ与える番号。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 動く形の識別子(u64);

impl 動く形の識別子 {
    /// 利用者が決めた番号から作る。索引の中で重複しないことは、登録の側が確かめる。
    pub fn 番号から生成する(番号: u64) -> Self {
        Self(番号)
    }

    /// 利用者が決めた番号。
    pub fn 番号(&self) -> u64 {
        self.0
    }
}
