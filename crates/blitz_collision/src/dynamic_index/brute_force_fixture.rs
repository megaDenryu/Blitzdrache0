//! 見本の集まりから、階層を使わずに総当たりで答えを組む工程。受け取るのは索引と覆い、返すのは識別子の昇順に
//! 並んだ答えである。
//!
//! 比べる相手をゆとり付きの箱にするのは、索引が木へ載せているのがその箱だからである。実体の箱で総当たりを組むと、
//! 木の辿り方の誤りとゆとりの効き方の違いが1つの食い違いに混ざり、どちらが原因か分からなくなる。ゆとりが実体を
//! 包むことは別の反証が見る。
//! 参照: `crates/blitz_collision/src/dynamic_index/margin_tests.rs`

#![cfg(test)]

use crate::shape::大域の軸平行の直方体;

use super::identifier::動く形の識別子;
use super::index::動く形の空間索引;
use super::pair::重なりうる形の対;
use super::sample_fixture::動く形の見本;

impl 動く形の見本 {
    pub(super) fn 覆いに触れうる識別子を総当たりで求める(
        &self,
        索引: &動く形の空間索引,
        覆い: &大域の軸平行の直方体,
    ) -> Vec<動く形の識別子> {
        let mut 答え: Vec<動く形の識別子> = self
            .一覧()
            .iter()
            .filter(|(_, 実体の箱)| 索引.ゆとり付きの箱を求める(実体の箱).相手と交わるか(覆い))
            .map(|(識別子, _)| *識別子)
            .collect();
        答え.sort_unstable();
        答え
    }

    pub(super) fn 重なりうる対を総当たりで求める(&self, 索引: &動く形の空間索引) -> Vec<重なりうる形の対> {
        let ゆとり付き: Vec<(動く形の識別子, 大域の軸平行の直方体)> = self
            .一覧()
            .iter()
            .map(|(識別子, 実体の箱)| (*識別子, 索引.ゆとり付きの箱を求める(実体の箱)))
            .collect();
        let mut 答え = Vec::new();
        for (先の位置, (一方の識別子, 一方の箱)) in ゆとり付き.iter().enumerate() {
            for (他方の識別子, 他方の箱) in ゆとり付き.iter().skip(先の位置 + 1) {
                if 一方の箱.相手と交わるか(他方の箱) {
                    答え.push(重なりうる形の対::二つの識別子から生成する(
                        *一方の識別子,
                        *他方の識別子,
                    ));
                }
            }
        }
        答え.sort_unstable();
        答え
    }
}
