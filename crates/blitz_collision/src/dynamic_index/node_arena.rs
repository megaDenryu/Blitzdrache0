//! 動く形の木のノードの置き場: ノードを1本の列で持ち、取り除いた枠を使い回す。
//!
//! 触れるフィールドは枠の列と、次に使える空き枠の位置の2つだけである。木の形(どのノードがどのノードの子か)は
//! ここでは扱わず、枠の貸し借りだけを受け持つ。
//!
//! ノードを1本の列で持ち、子を位置で指すのは、ノード1つにつき確保が起きるのを避けるためである。取り除いた枠を
//! 使い回すのは、形の出し入れを繰り返す索引で列が際限なく伸びるのを避けるためである。使い回しの順は、
//! 取り除いた順の逆(最後に空いた枠から先に使う)であり、同じ操作列からは必ず同じ枠が同じ順で選ばれる。
//! 空き枠を数珠つなぎにする位置を空いた枠自身に置くため、使い回しのための別の列は要らない。
//!
//! 注意: 取り除いた枠を読むと、破れた不変条件を書いて即座に止まる。位置の出どころは、木が持つ親子の連なりと、
//! 索引が持つ識別子ごとの葉の対応表の2つしかなく、どちらも取り除いた枠を指し続けないことを自分で保つ。
//! 指し続けた状態は、答えを静かに間違える形ではなく、木の連なりが壊れているという到達しないはずの状態である。

use super::node::{動く形の木のノード, 動く形の木のノードの位置};

// 列の1枠。ノードが入っているか、次に使える空き枠を指しているかのどちらかである。
#[derive(Debug, Clone, Copy)]
enum ノードの枠 {
    使用中(動く形の木のノード),
    空き { 次に使える空き枠: Option<動く形の木のノードの位置> },
}

pub(super) struct 動く形の木のノードの置き場 {
    枠: Vec<ノードの枠>,
    次に使える空き枠: Option<動く形の木のノードの位置>,
}

impl 動く形の木のノードの置き場 {
    pub(super) fn 空の置き場から始める() -> Self {
        Self {
            枠: Vec::new(), 次に使える空き枠: None
        }
    }

    // ノードを1つ置き、その位置を返す。空き枠があればそこへ置き、無ければ列の末尾へ足す。
    pub(super) fn ノードを1つ置く(&mut self, ノード: 動く形の木のノード) -> 動く形の木のノードの位置 {
        let Some(空き) = self.次に使える空き枠 else {
            self.枠.push(ノードの枠::使用中(ノード));
            return 動く形の木のノードの位置::生成する(self.枠.len() - 1);
        };
        self.次に使える空き枠 = match self.枠[空き.列の中の位置()] {
            ノードの枠::空き { 次に使える空き枠 } => 次に使える空き枠,
            ノードの枠::使用中(_) => panic!("動く形の木の置き場が、使用中の枠を空き枠の連なりへ繋いでいる"),
        };
        self.枠[空き.列の中の位置()] = ノードの枠::使用中(ノード);
        空き
    }

    // ノードを1つ取り除き、その枠を空き枠の連なりの先頭へ繋ぐ。
    pub(super) fn ノードを1つ取り除く(&mut self, 位置: 動く形の木のノードの位置) {
        self.枠[位置.列の中の位置()] = ノードの枠::空き {
            次に使える空き枠: self.次に使える空き枠
        };
        self.次に使える空き枠 = Some(位置);
    }

    pub(super) fn ノードを読む(&self, 位置: 動く形の木のノードの位置) -> 動く形の木のノード {
        match self.枠[位置.列の中の位置()] {
            ノードの枠::使用中(ノード) => ノード,
            ノードの枠::空き { .. } => panic!("動く形の木が、取り除いた枠を指したままである"),
        }
    }

    pub(super) fn ノードを書き換える(&mut self, 位置: 動く形の木のノードの位置, ノード: 動く形の木のノード) {
        self.枠[位置.列の中の位置()] = ノードの枠::使用中(ノード);
    }
}
