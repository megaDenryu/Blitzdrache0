//! ゆとりの幅の主張と、その反証。ゆとりの中に居る間は木を触らないこと、越えたら挿し直すこと、包含の判定が
//! 端の一致を含むこと、そして遠い座標でも広げた箱が実体の箱を丸ごと含むことを見る。
//!
//! 主張と反証を対で置く。ゆとりの中の移動が木を触らないという主張だけでは、包含の判定をつねに真にした実装でも
//! 通る。越えた移動が挿し直すという反証がそれを落とす。広げた箱が実体を含むという主張だけでは、広げる向きが
//! 効いているかが分からない。向きを内へ取った箱が実体を含まないことを見る反証がそれを示す。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use crate::shape::大域の軸平行の直方体;

use super::identifier::動く形の識別子;
use super::index::動く形の空間索引;
use super::margin::箱に持たせるゆとりの幅;
use super::pseudo_random_fixture::決まった種から進む擬似乱数;
use super::sample_fixture::{中心と半分の長さから箱を組む, 端の成分から箱を組む};
use super::update_result::箱の更新で木を組み替えたか;

// 遠い座標の反証が使う中心の距離であるメートル。倍精度の刻みがミリメートルより粗くなる桁を選ぶ。
const 遠い座標のメートル: f64 = 1.0e7;

fn 既定の幅の索引() -> 動く形の空間索引 {
    動く形の空間索引::ゆとりの幅から生成する(箱に持たせるゆとりの幅::人型と家具の大きさに見合う既定の幅())
}

fn 一つだけ登録した索引(実体の箱: &大域の軸平行の直方体) -> 動く形の空間索引 {
    let mut 索引 = 既定の幅の索引();
    索引.形を1つ登録する(動く形の識別子::番号から生成する(1), 実体の箱).unwrap();
    索引
}

#[test]
fn ゆとりの中の移動では木を1節点も触らない() {
    let 実体の箱 = 中心と半分の長さから箱を組む([0.0, 0.0, 0.0], [1.0, 1.0, 1.0]);
    let mut 索引 = 一つだけ登録した索引(&実体の箱);
    let 動かした箱 = 中心と半分の長さから箱を組む([0.05, -0.05, 0.02], [1.0, 1.0, 1.0]);
    let 結果 = 索引.形の箱を更新する(動く形の識別子::番号から生成する(1), &動かした箱).unwrap();
    assert_eq!(結果, 箱の更新で木を組み替えたか::構造を触らなかった);
}

#[test]
fn ゆとりを越える移動では葉を挿し直す() {
    let 実体の箱 = 中心と半分の長さから箱を組む([0.0, 0.0, 0.0], [1.0, 1.0, 1.0]);
    let mut 索引 = 一つだけ登録した索引(&実体の箱);
    let 動かした箱 = 中心と半分の長さから箱を組む([0.2, 0.0, 0.0], [1.0, 1.0, 1.0]);
    let 結果 = 索引.形の箱を更新する(動く形の識別子::番号から生成する(1), &動かした箱).unwrap();
    assert_eq!(結果, 箱の更新で木を組み替えたか::葉を挿し直した);
}

#[test]
fn 実体の端がゆとり付きの端にちょうど届いても木を触らず1刻み越えると挿し直す() {
    let 実体の箱 = 中心と半分の長さから箱を組む([0.0, 0.0, 0.0], [1.0, 1.0, 1.0]);
    let mut 索引 = 一つだけ登録した索引(&実体の箱);
    let ゆとり付きの端 = 索引.ゆとり付きの箱を求める(&実体の箱).最大の端().x().値();
    let 端まで届く箱 = 端の成分から箱を組む([-1.0, -1.0, -1.0], [ゆとり付きの端, 1.0, 1.0]);
    let 届いた結果 = 索引.形の箱を更新する(動く形の識別子::番号から生成する(1), &端まで届く箱).unwrap();
    assert_eq!(届いた結果, 箱の更新で木を組み替えたか::構造を触らなかった);
    let 刻み1つ越えた端 = f64::from_bits(ゆとり付きの端.to_bits() + 1);
    let 越えた箱 = 端の成分から箱を組む([-1.0, -1.0, -1.0], [刻み1つ越えた端, 1.0, 1.0]);
    let 越えた結果 = 索引.形の箱を更新する(動く形の識別子::番号から生成する(1), &越えた箱).unwrap();
    assert_eq!(越えた結果, 箱の更新で木を組み替えたか::葉を挿し直した);
}

#[test]
fn 遠い座標でも広げた箱は実体の箱を丸ごと含む() {
    let 索引 = 既定の幅の索引();
    let mut 乱数 = 決まった種から進む擬似乱数::種から始める(41);
    for _ in 0..10_000 {
        let 中心 = [0usize, 1, 2].map(|_| 乱数.範囲の中の値(-遠い座標のメートル, 遠い座標のメートル));
        let 半分の長さ = [0usize, 1, 2].map(|_| 乱数.範囲の中の値(0.0, 5.0));
        let 実体の箱 = 中心と半分の長さから箱を組む(中心, 半分の長さ);
        assert!(
            索引.ゆとり付きの箱を求める(&実体の箱).相手を丸ごと含むか(&実体の箱),
            "中心{中心:?}で広げた箱が実体を含まない"
        );
    }
}

#[test]
fn 広げる向きを内へ取ると遠い座標で実体の箱がはみ出す() {
    let 実体の箱 = 中心と半分の長さから箱を組む([遠い座標のメートル, 0.0, 0.0], [1.0, 1.0, 1.0]);
    let 幅 = 箱に持たせるゆとりの幅::人型と家具の大きさに見合う既定の幅().幅().値();
    let 内へ取った箱 = 実体の箱.全方向へ広げた箱を求める(メートル::生成する(-幅));
    assert!(
        !内へ取った箱.相手を丸ごと含むか(&実体の箱),
        "向きを内へ取っても実体を含んでおり、外向きの固定が効いていない"
    );
}
