//! 箱の更新で木を組み替えたか: 実体の箱を更新したときに、木の構造を触ったかどうかの答えである。
//!
//! 真偽値でなく2つの枝を持つ型にするのは、呼び出し側が受け取るのが「木を触ったか」という事実であって、
//! 何かが成功したかではないためである。枝の名前が起きたことをそのまま述べるため、受け取った側で真がどちらを
//! 指すのかを覚え直さなくてよい。
//!
//! この答えを返す理由は、ゆとりの幅が効いているかを利用者が測れるようにするためである。毎刻みほとんどの形が
//! 挿し直しを返すなら、幅がその物体の1刻みの移動に対して小さすぎる。

/// 実体の箱を更新したときに、木の構造を触ったかどうか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 箱の更新で木を組み替えたか {
    /// 実体の箱がゆとり付きの箱の中に残っていたため、木の構造を1節点も触らなかった。
    構造を触らなかった,
    /// 実体の箱がゆとり付きの箱からはみ出たため、葉を1枚外して挿し直した。
    葉を挿し直した,
}
