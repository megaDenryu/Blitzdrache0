//! 動く形の空間索引で破れる条件。ゆとりの幅を作るときの破れ、形を出し入れするときの破れ、問い合わせるときの破れを
//! 3つの型に分ける。
//!
//! 3つに分けるのは、直す場所が違うためである。幅の破れは索引を組む配線を直すことでしか消えず、出し入れの破れは
//! 呼び出し側の台帳と索引の食い違いを直すことで消え、問い合わせの破れは問い合わせの入力か木の組み立てを直すことで
//! 消える。
//!
//! 端がどの軸で破れたかを持たないのは、この3つがどれも呼び出し側の配線の誤りであり、軸を知っても直す場所が
//! 変わらないためである。直方体の生成の側が軸を持つのは、あちらが焼き込みの入力を1件ずつ突き返す用途を持つためである。

use thiserror::Error;

use super::identifier::動く形の識別子;

/// ゆとりの幅の生成が拒む理由。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 箱に持たせるゆとりの幅の生成エラー {
    /// 幅が有限でない。
    #[error("箱に持たせるゆとりの幅が有限でない")]
    幅が有限でない,
    /// 幅が0以下である。ゆとりが0の索引は、形が動くたびに木を組み替える。
    #[error("箱に持たせるゆとりの幅が0以下である")]
    幅が0以下,
    /// 幅が形状の座標の絶対値の上限を越えた。
    #[error("箱に持たせるゆとりの幅が形状の座標の上限を越えた")]
    幅が上限を越えている,
}

/// 動く形の登録・除去・箱の更新が拒む理由。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 動く形の空間索引の操作エラー {
    /// 同じ識別子の形が既に登録されている。
    #[error("識別子{}の動く形は既に登録されている", .識別子.番号())]
    識別子が既に登録されている {
        /// 重なった識別子。
        識別子: 動く形の識別子,
    },
    /// その識別子の形が登録されていない。除去と箱の更新がこれを返す。
    #[error("識別子{}の動く形は登録されていない", .識別子.番号())]
    識別子が登録されていない {
        /// 見つからなかった識別子。
        識別子: 動く形の識別子,
    },
    /// 実体の箱の端に有限でない成分が含まれる。
    #[error("動く形の実体の箱の端に有限でない値が含まれる")]
    実体の箱の端が有限でない,
    /// 実体の箱の最小の端が最大の端を越えた。
    #[error("動く形の実体の箱で最小の端が最大の端を越えている")]
    実体の箱の最小が最大を越えている,
}

/// 動く形の索引への問い合わせで破れる条件。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 動く形の空間索引の問い合わせエラー {
    /// 覆いの端に有限でない成分が含まれる。
    #[error("動く形の索引へ渡した覆いの端に有限でない値が含まれる")]
    覆いの端が有限でない,
    /// 木を辿るスタックが上限を越えた。木の深さが上限に収まることを組み替えが保証するため、到達したら木が壊れている。
    #[error("動く形の木を辿るスタックが上限を越えた")]
    走査のスタックが上限を越えている,
}
