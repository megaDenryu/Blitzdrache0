//! 動く形の木の節点と、その節点を指す位置と、節点の中身。3つを1つのファイルに置くのは、どれも「木の中のどこを
//! 指すか」という1つの概念を成し、互いを見ずには意味が決まらないためである。
//!
//! 節点は自分の境界と中身と親と部分木の高さを持つ。中身は、2つの子を指す内部節点か、動く形1つの識別子を持つ葉の
//! どちらかである。判別共用体にするのは、内部節点だけが子を持ち葉だけが識別子を持つという排他を型で表すためである。
//!
//! 親を持つのは、葉を外すときに兄弟を親の位置へ繰り上げ、そこから根まで境界と高さを整え直すためである。親を
//! 持たない木では、葉から根への道を根からの再探索で作り直すことになる。
//!
//! 部分木の高さを持つのは、左右の高さの差が1を越えた節点を組み替えの対象にするためである。葉の高さは0であり、
//! 内部節点の高さは2つの子の高さの大きいほうに1を足した値である。
//!
//! 子を`[位置; 2]`で持つのは、組み替えが「高いほうの子を持ち上げ、低いほうの孫を元の節点へ渡す」という左右で同じ
//! 手順を踏み、並びの位置を渡すだけで左右のどちらでも同じ1つの経路で書けるためである。並びの位置は木の中でだけ
//! 意味を持ち、外へ出ない。走査は並びの順に積むため、並びは列挙の順にも効く。
//!
//! 差し替えが新しい節点を返す形なのは、節点が`Copy`であり、置き場が持つ枠へ書き戻す側が1箇所に決まるためである。
//! 節点そのものへ可変の借りを配ると、木を辿りながら別の節点を書き換える経路が作れてしまう。

use crate::shape::大域の軸平行の直方体;

use super::identifier::動く形の識別子;

// 置き場が持つ枠の列の中の位置。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 動く形の木の節点の位置(usize);

impl 動く形の木の節点の位置 {
    pub(super) fn 生成する(列の中の位置: usize) -> Self {
        Self(列の中の位置)
    }

    pub(super) fn 列の中の位置(&self) -> usize {
        self.0
    }
}

// 節点の中身。2つの子を指す内部節点か、動く形1つの識別子を持つ葉のどちらかである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 節点の中身 {
    内部 { 子: [動く形の木の節点の位置; 2] },
    葉 { 識別子: 動く形の識別子 },
}

// 木の節点1つ。配下の形をすべて包む境界と、中身と、親と、部分木の高さを持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 動く形の木の節点 {
    境界: 大域の軸平行の直方体,
    中身: 節点の中身,
    親: Option<動く形の木の節点の位置>,
    部分木の高さ: u32,
}

impl 動く形の木の節点 {
    // 葉を1つ作る。親はまだ決まっておらず、木へ挿す側が差し替える。
    pub(super) fn 葉として生成する(境界: 大域の軸平行の直方体, 識別子: 動く形の識別子) -> Self {
        Self {
            境界,
            中身: 節点の中身::葉 { 識別子 },
            親: None,
            部分木の高さ: 0,
        }
    }

    // 内部節点を1つ作る。境界と高さは2つの子から作った値を受け取る。
    pub(super) fn 内部として生成する(
        境界: 大域の軸平行の直方体,
        子: [動く形の木の節点の位置; 2],
        親: Option<動く形の木の節点の位置>,
        部分木の高さ: u32,
    ) -> Self {
        Self {
            境界,
            中身: 節点の中身::内部 { 子 },
            親,
            部分木の高さ,
        }
    }

    pub(super) fn 境界(&self) -> 大域の軸平行の直方体 {
        self.境界
    }

    pub(super) fn 中身(&self) -> 節点の中身 {
        self.中身
    }

    pub(super) fn 親(&self) -> Option<動く形の木の節点の位置> {
        self.親
    }

    pub(super) fn 部分木の高さ(&self) -> u32 {
        self.部分木の高さ
    }

    pub(super) fn 親を差し替えた節点(&self, 親: Option<動く形の木の節点の位置>) -> Self {
        Self { 親, ..*self }
    }

    pub(super) fn 境界と高さを差し替えた節点(&self, 境界: 大域の軸平行の直方体, 部分木の高さ: u32) -> Self {
        Self {
            境界, 部分木の高さ, ..*self
        }
    }

    // 並びの位置が指す子を差し替えた節点。葉は子を持たないため、そのまま返す。
    pub(super) fn 子を差し替えた節点(&self, 並びの位置: usize, 新しい子: 動く形の木の節点の位置) -> Self {
        match self.中身 {
            節点の中身::内部 { mut 子 } => {
                子[並びの位置] = 新しい子;
                Self {
                    中身: 節点の中身::内部 { 子 },
                    ..*self
                }
            }
            節点の中身::葉 { .. } => *self,
        }
    }
}
