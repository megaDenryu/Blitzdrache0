//! 木が満たすべき不変条件の検査。受け取るのは索引、返すものは無く、破れたらその場で落ちる。
//!
//! 見るのは5つである。根が親を持たないこと、内部節点の境界が2つの子の境界を丸ごと包むこと、子の親が自分を
//! 指し返すこと、内部節点の高さが子の高さの大きいほうに1を足した値であること、左右の部分木の高さの差が
//! 1以内であることである。最後の1つが破れると、走査のスタックの上限の根拠が崩れる。
//!
//! 葉の数を数えて登録件数と突き合わせるのは、葉を外す操作が木から外し損ねた葉や、二重に数えられる葉を
//! 検出するためである。

#![cfg(test)]

use super::index::動く形の空間索引;
use super::node::{動く形の木の節点の位置, 節点の中身};
use super::tree::動く形の境界箱の木;

impl 動く形の空間索引 {
    pub(super) fn 木の不変条件を確かめる(&self) {
        let Some(根) = self.木().根() else {
            assert_eq!(self.登録件数(), 0, "木が空なのに形が登録されている");
            return;
        };
        assert!(self.木().節点を読む(根).親().is_none(), "根が親を指している");
        let 葉の数 = self.木().節点から下の不変条件を確かめる(根);
        assert_eq!(葉の数, self.登録件数(), "木の葉の数が登録件数と食い違う");
    }
}

impl 動く形の境界箱の木 {
    // 与えられた節点から下を辿り、葉の数を返す。
    fn 節点から下の不変条件を確かめる(&self, 位置: 動く形の木の節点の位置) -> usize {
        let 節点 = self.節点を読む(位置);
        let 節点の中身::内部 { 子 } = 節点.中身() else {
            assert_eq!(節点.部分木の高さ(), 0, "葉の高さが0でない");
            return 1;
        };
        let mut 葉の数 = 0;
        for 子の位置 in 子 {
            let 子の節点 = self.節点を読む(子の位置);
            assert_eq!(子の節点.親(), Some(位置), "子が別の親を指している");
            assert!(節点.境界().相手を丸ごと含むか(&子の節点.境界()), "節点の境界が子の境界を包んでいない");
            葉の数 += self.節点から下の不変条件を確かめる(子の位置);
        }
        let 子の高さ = 子.map(|子の位置| i64::from(self.節点を読む(子の位置).部分木の高さ()));
        assert_eq!(
            i64::from(節点.部分木の高さ()),
            子の高さ[0].max(子の高さ[1]) + 1,
            "内部節点の高さが子の高さと食い違う"
        );
        assert!((子の高さ[0] - 子の高さ[1]).abs() <= 1, "左右の部分木の高さの差が1を越えている");
        葉の数
    }
}
