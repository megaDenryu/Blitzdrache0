//! 覆いに触れる葉の走査: 覆いの箱1つを受け取り、それに境界が触れる葉の識別子を1つずつ渡すセッション型である。
//!
//! コールバックを渡す形にしないのは、走査の側が「次を1つ出す」以上のことを決めていないためである。何を渡された
//! ときに何をするかは問い合わせの側が決める。覆いの問い合わせと重なりうる対の列挙がこの1つの走査を共有し、
//! 木の辿り方はここ1箇所になる。
//!
//! 辿り方は、根から始めて境界が覆いと交わる節点だけを下る深さ優先である。積むのは固定の長さのスタックであり、
//! 確保は1度も起きない。走る順は、節点を取り出したときに並びの順で積み、後に積んだほうから取り出す順である。
//!
//! 答えの並びをこの走る順に頼らないのは、木の形が登録と除去の順で変わるためである。集めた識別子は呼び出し側が
//! 昇順へ並べ直し、同じ集合ならどの木からも同じ並びで返る形にする。
//! 参照: `crates/blitz_collision/src/dynamic_index/index_query.rs`

use crate::shape::大域の軸平行の直方体;

use super::error::動く形の空間索引の問い合わせエラー;
use super::identifier::動く形の識別子;
use super::node::節点の中身;
use super::traversal_stack::動く形の木の走査のスタック;
use super::tree::動く形の境界箱の木;

pub(super) struct 覆いに触れる葉の走査<'木> {
    木: &'木 動く形の境界箱の木,
    覆い: 大域の軸平行の直方体,
    スタック: 動く形の木の走査のスタック,
}

impl<'木> 覆いに触れる葉の走査<'木> {
    pub(super) fn 根から始める(
        木: &'木 動く形の境界箱の木,
        覆い: 大域の軸平行の直方体,
    ) -> Result<Self, 動く形の空間索引の問い合わせエラー> {
        let mut スタック = 動く形の木の走査のスタック::空の状態から始める();
        if let Some(根) = 木.根() {
            スタック.積む(根)?;
        }
        Ok(Self { 木, 覆い, スタック })
    }

    // 次の候補の識別子。覆いに触れる葉をすべて出し切ったら値なしを返す。
    pub(super) fn 次の葉の識別子を取り出す(
        &mut self,
    ) -> Result<Option<動く形の識別子>, 動く形の空間索引の問い合わせエラー> {
        while let Some(位置) = self.スタック.取り出す() {
            let 節点 = self.木.節点を読む(位置);
            if !節点.境界().相手と交わるか(&self.覆い) {
                continue;
            }
            match 節点.中身() {
                節点の中身::内部 { 子 } => {
                    self.スタック.積む(子[0])?;
                    self.スタック.積む(子[1])?;
                }
                節点の中身::葉 { 識別子 } => return Ok(Some(識別子)),
            }
        }
        Ok(None)
    }
}
