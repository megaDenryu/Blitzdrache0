//! 決定性の反証。同じ操作列を2回流して木の形そのものと列挙の並びが一致すること、および登録の順を変えても
//! 列挙の並びが変わらないことを見る。
//!
//! 2つを分けて見るのは、主張が2段になっているためである。1段目は「同じ操作列からは同じ構造」であり、木の形を
//! 綴りへ書き出して突き合わせる。2段目は「同じ集合からは同じ並び」であり、こちらは木の形が違っても成り立たな
//! ければならない。答えの並びだけを比べると1段目を見逃し、木の形だけを比べると2段目を見逃す。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断14: 決定性の維持」

#![allow(clippy::unwrap_used)]

use super::index::動く形の空間索引;
use super::margin::箱に持たせるゆとりの幅;
use super::pair::重なりうる形の対;
use super::sample_fixture::{中心と半分の長さから箱を組む, 動く形の見本};

fn 既定の幅の索引() -> 動く形の空間索引 {
    動く形の空間索引::ゆとりの幅から生成する(箱に持たせるゆとりの幅::人型と家具の大きさに見合う既定の幅())
}

// 登録と、5件ごとの除去と、7件ごとの遠くへの移動を、この順で流す。
fn 決まった操作列を流す(見本: &動く形の見本, 逆順で登録するか: bool) -> 動く形の空間索引 {
    let mut 索引 = 既定の幅の索引();
    let mut 一覧: Vec<_> = 見本.一覧().to_vec();
    if 逆順で登録するか {
        一覧.reverse();
    }
    for (識別子, 実体の箱) in &一覧 {
        索引.形を1つ登録する(*識別子, 実体の箱).unwrap();
    }
    for (順番, (識別子, _)) in 一覧.iter().enumerate() {
        if 順番 % 5 == 0 {
            索引.形を1つ除去する(*識別子).unwrap();
        } else if 順番 % 7 == 0 {
            索引
                .形の箱を更新する(*識別子, &中心と半分の長さから箱を組む([200.0, 0.0, 0.0], [1.0, 1.0, 1.0]))
                .unwrap();
        }
    }
    索引
}

fn 対の一覧(索引: &動く形の空間索引) -> Vec<重なりうる形の対> {
    let mut 受け皿 = Vec::new();
    索引.重なりうる形の対を集める(&mut 受け皿).unwrap();
    受け皿
}

#[test]
fn 同じ操作列からは同じ木と同じ並びが出る() {
    let 見本 = 動く形の見本::無作為な箱から作る(180, 31);
    let 一度目 = 決まった操作列を流す(&見本, false);
    let 二度目 = 決まった操作列を流す(&見本, false);
    assert_eq!(一度目.木の形を綴りへ書き出す(), 二度目.木の形を綴りへ書き出す());
    assert_eq!(対の一覧(&一度目), 対の一覧(&二度目));
}

#[test]
fn 登録の順が違っても列挙の並びは識別子の昇順で揃う() {
    let 見本 = 動く形の見本::無作為な箱から作る(120, 32);
    let mut 順に登録した索引 = 既定の幅の索引();
    見本.索引へ登録する(&mut 順に登録した索引);
    let mut 逆順に登録した索引 = 既定の幅の索引();
    for (識別子, 実体の箱) in 見本.一覧().iter().rev() {
        逆順に登録した索引.形を1つ登録する(*識別子, 実体の箱).unwrap();
    }
    assert_ne!(
        順に登録した索引.木の形を綴りへ書き出す(),
        逆順に登録した索引.木の形を綴りへ書き出す(),
        "登録の順を変えても木の形が同じであり、この反証が2段目を見ていない"
    );
    assert_eq!(対の一覧(&順に登録した索引), 対の一覧(&逆順に登録した索引));
}
