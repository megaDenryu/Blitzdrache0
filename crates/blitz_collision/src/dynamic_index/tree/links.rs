//! 木の親子の付け替えと、内部ノードの境界と高さの作り直し。触れるのはノードの親・子・境界・部分木の高さであり、
//! どの葉がどの形かには触れない。
//!
//! 不変条件: 親の付け替えと子の差し替えは対で呼ぶ。片方だけを呼ぶと、根から辿った先のノードが別の親を指す木ができる。
//! 対で呼ぶことは、葉を挿す操作・葉を外す操作・子を1段持ち上げる操作の3つがそれぞれ自分の中で守る。

use super::super::node::{ノードの中身, 動く形の木のノードの位置};
use super::動く形の境界箱の木;

impl 動く形の境界箱の木 {
    pub(super) fn 親を書き換える(&mut self, 位置: 動く形の木のノードの位置, 親: Option<動く形の木のノードの位置>) {
        let ノード = self.ノードを読む(位置);
        self.置き場.ノードを書き換える(位置, ノード.親を差し替えたノード(親));
    }

    // 親が持つ2つの子のうち、古い子を指していたほうを新しい子へ差し替える。
    pub(super) fn 親の子を差し替える(&mut self, 親: 動く形の木のノードの位置, 古い子: 動く形の木のノードの位置, 新しい子: 動く形の木のノードの位置) {
        let ノード = self.ノードを読む(親);
        let 並びの位置 = if self.内部の子を読む(親)[0] == 古い子 { 0 } else { 1 };
        self.置き場.ノードを書き換える(親, ノード.子を差し替えたノード(並びの位置, 新しい子));
    }

    // 親が持つ2つの子のうち、一方でないほう。葉を外すときに繰り上げる兄弟をこれで求める。
    pub(super) fn もう一方の子を求める(&self, 親: 動く形の木のノードの位置, 一方: 動く形の木のノードの位置) -> 動く形の木のノードの位置 {
        let 子 = self.内部の子を読む(親);
        if 子[0] == 一方 { 子[1] } else { 子[0] }
    }

    // 内部ノードが持つ2つの子。葉を渡したら木の連なりが壊れているため、破れた不変条件を書いて止まる。
    pub(super) fn 内部の子を読む(&self, 位置: 動く形の木のノードの位置) -> [動く形の木のノードの位置; 2] {
        match self.ノードを読む(位置).中身() {
            ノードの中身::内部 { 子 } => 子,
            ノードの中身::葉 { .. } => panic!("動く形の木が、葉を内部ノードとして辿っている"),
        }
    }

    // 内部ノードの境界と高さを、今の2つの子から作り直す。葉には何もしない。
    pub(super) fn 境界と高さを子から作り直す(&mut self, 位置: 動く形の木のノードの位置) {
        let ノード = self.ノードを読む(位置);
        let ノードの中身::内部 { 子 } = ノード.中身() else {
            return;
        };
        let 一方 = self.ノードを読む(子[0]);
        let 他方 = self.ノードを読む(子[1]);
        let 境界 = 一方.境界().相手を含む箱を求める(&他方.境界());
        let 高さ = 一方.部分木の高さ().max(他方.部分木の高さ()) + 1;
        self.置き場.ノードを書き換える(位置, ノード.境界と高さを差し替えたノード(境界, 高さ));
    }
}
