//! 葉を挿した後と外した後に、触った節点から根まで辿って境界と高さを整え、左右の高さの差が1を越えた節点を組み替える工程。
//!
//! 呼び出しタイミングは、葉を1枚挿した直後と1枚外した直後だけである。形が動いてもゆとりの中に居る間は呼ばれない。
//!
//! 組み替えは、高いほうの子を1段持ち上げ、その子の下にあった2つのうち低いほうを元の節点へ渡す1回転である。
//! 回転は左右で同じ手順であり、持ち上げる子の並びの位置を渡すだけで1つの経路に収まる。持ち上げる子の並びを
//! i と書くと、持ち上げた子の並び i が高いほうの孫、並び 1-i が元の節点になり、元の節点の並び i が低いほうの孫になる。
//!
//! 深さの上界。左右の高さの差を1以内に保つ木では、高さ h の木が持つ葉の数が下からフィボナッチ数で押さえられ、
//! 高さは葉の数の2を底とする対数のおよそ1.44倍に収まる。この性質から、走査のスタックの上限128がどの実在しうる木
//! よりも深い木まで辿れることまでの導出は、上限を持つ側の1箇所にある。数え方も高さの上界の値もそちらが正本である。
//! 参照: `crates/blitz_collision/src/dynamic_index/traversal_stack.rs`
//!
//! 決定性: 持ち上げる向きは高さの差の符号だけで決まり、孫のどちらを残すかは高さの比較だけで決まる。高さが並んだ
//! ときは並びの後ろの孫を持ち上げた子に残す。どれも入力だけで決まる。

use super::super::node::動く形の木の節点の位置;
use super::動く形の境界箱の木;

impl 動く形の境界箱の木 {
    // 与えられた節点から根まで辿り、節点ごとに組み替えと境界と高さの作り直しを行う。
    pub(super) fn 高さと境界を根まで整える(&mut self, 始まりの位置: 動く形の木の節点の位置) {
        let mut 今の位置 = Some(始まりの位置);
        while let Some(位置) = 今の位置 {
            let 整えた位置 = self.高さの差が開いていれば組み替える(位置);
            self.境界と高さを子から作り直す(整えた位置);
            今の位置 = self.節点を読む(整えた位置).親();
        }
    }

    // 左右の高さの差が1を越えていれば高いほうの子を1段持ち上げる。返すのは、この部分木の新しい根の位置である。
    fn 高さの差が開いていれば組み替える(&mut self, 位置: 動く形の木の節点の位置) -> 動く形の木の節点の位置 {
        if self.節点を読む(位置).部分木の高さ() < 2 {
            return 位置;
        }
        let 子 = self.内部の子を読む(位置);
        let 高さ = 子.map(|子の位置| i64::from(self.節点を読む(子の位置).部分木の高さ()));
        let 高さの差 = 高さ[1] - 高さ[0];
        if 高さの差 > 1 {
            return self.子を1段持ち上げる(位置, 1);
        }
        if 高さの差 < -1 {
            return self.子を1段持ち上げる(位置, 0);
        }
        位置
    }

    // 並びの位置が指す子を1段持ち上げる。高さの差が2以上ある内部節点でだけ呼ぶため、持ち上げる子も内部節点である。
    fn 子を1段持ち上げる(&mut self, 位置: 動く形の木の節点の位置, 並びの位置: usize) -> 動く形の木の節点の位置 {
        let 持ち上げる子 = self.内部の子を読む(位置)[並びの位置];
        let 孫 = self.内部の子を読む(持ち上げる子);
        let 孫の高さ = 孫.map(|孫の位置| self.節点を読む(孫の位置).部分木の高さ());
        let (残す孫, 渡す孫) = if 孫の高さ[0] > 孫の高さ[1] {
            (孫[0], 孫[1])
        } else {
            (孫[1], 孫[0])
        };
        let 祖父 = self.節点を読む(位置).親();
        self.子を書き換える(位置, 並びの位置, 渡す孫);
        self.親を書き換える(渡す孫, Some(位置));
        self.子を書き換える(持ち上げる子, 並びの位置, 残す孫);
        self.子を書き換える(持ち上げる子, 1 - 並びの位置, 位置);
        self.親を書き換える(位置, Some(持ち上げる子));
        self.親を書き換える(持ち上げる子, 祖父);
        match 祖父 {
            Some(祖父の位置) => self.親の子を差し替える(祖父の位置, 位置, 持ち上げる子),
            None => self.根 = Some(持ち上げる子),
        }
        self.境界と高さを子から作り直す(位置);
        self.境界と高さを子から作り直す(持ち上げる子);
        持ち上げる子
    }

    // 並びの位置が指す子を差し替える。持ち上げの手順だけが使う。
    fn 子を書き換える(
        &mut self, 位置: 動く形の木の節点の位置, 並びの位置: usize, 新しい子: 動く形の木の節点の位置
    ) {
        let 節点 = self.節点を読む(位置);
        self.置き場.節点を書き換える(位置, 節点.子を差し替えた節点(並びの位置, 新しい子));
    }
}
