//! 葉を挿す先の兄弟を選ぶ工程。受け取るのは下り始める節点と挿す箱、返すのは新しい内部節点の下へ入る兄弟の位置である。
//!
//! 尺度は包む箱の表面積である。挿す箱と兄弟を1つの内部節点で束ねると、その節点の境界は2つを包む箱になり、
//! 以後その節点を通る問い合わせはすべてその箱と比べられる。箱が大きいほど当たらない候補が増えるから、
//! 束ねたときに増える表面積がいちばん小さい相手を選ぶ。
//!
//! 下りるか止まるかは、その節点そのものと束ねる費用と、子へ下って束ねる費用を比べて決める。節点そのものと
//! 束ねる費用は、新しく作る内部節点の表面積の2倍である(自分と親の両方にその箱が現れるため)。子へ下る費用は、
//! 子と束ねてできる箱の表面積から子の元の表面積を引いた増分に、途中の節点が育つぶんを足したものである。
//! 内部節点でない子(葉)には引くべき元の表面積が無いため、葉に対しては束ねた箱の表面積そのものを費用にする。
//!
//! 決定性: 2つの子の費用が等しいときは並びの先の子を選び、節点そのものと束ねる費用が子の費用と等しいときは
//! 下りる。どちらも入力だけで決まるため、同じ木と同じ箱からは必ず同じ兄弟が返る。

use crate::shape::大域の軸平行の直方体;

use super::super::node::{動く形の木の節点の位置, 節点の中身};
use super::動く形の境界箱の木;

impl 動く形の境界箱の木 {
    pub(super) fn 挿す先の兄弟を選ぶ(
        &self,
        下り始める位置: 動く形の木の節点の位置,
        挿す箱: &大域の軸平行の直方体,
    ) -> 動く形の木の節点の位置 {
        let mut 今の位置 = 下り始める位置;
        loop {
            let 節点 = self.節点を読む(今の位置);
            let 節点の中身::内部 { 子 } = 節点.中身() else {
                return 今の位置;
            };
            let 束ねた面積 = 節点.境界().相手を含む箱を求める(挿す箱).表面積の平方メートル();
            let ここで束ねる費用 = 2.0 * 束ねた面積;
            let 下る途中で育つ費用 = 2.0 * (束ねた面積 - 節点.境界().表面積の平方メートル());
            let 子ごとの費用 = 子.map(|子の位置| self.子と束ねる費用を求める(子の位置, 挿す箱) + 下る途中で育つ費用);
            if ここで束ねる費用 < 子ごとの費用[0] && ここで束ねる費用 < 子ごとの費用[1] {
                return 今の位置;
            }
            今の位置 = if 子ごとの費用[0] <= 子ごとの費用[1] {
                子[0]
            } else {
                子[1]
            };
        }
    }

    // 子1つと挿す箱を束ねたときの費用。内部節点なら増分、葉なら束ねた箱の表面積そのものである。
    fn 子と束ねる費用を求める(&self, 子の位置: 動く形の木の節点の位置, 挿す箱: &大域の軸平行の直方体) -> f64 {
        let 子 = self.節点を読む(子の位置);
        let 束ねた面積 = 子.境界().相手を含む箱を求める(挿す箱).表面積の平方メートル();
        match 子.中身() {
            節点の中身::内部 { .. } => 束ねた面積 - 子.境界().表面積の平方メートル(),
            節点の中身::葉 { .. } => 束ねた面積,
        }
    }
}
