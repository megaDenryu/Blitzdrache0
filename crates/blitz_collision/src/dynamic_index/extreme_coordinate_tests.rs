//! 座標の絶対値が倍精度の最大の桁に近い箱の反証。実体の箱の端が有限でも、ゆとりを足した端が有限でなくなる入力が
//! あることと、その入力が登録でも更新でも型付きエラーで返ることを見る。
//!
//! 実体の箱の端だけを見る検査と対で置く。端が有限な箱しか通さない検査だけでは、両端の絶対値の和が倍精度の範囲を
//! 出る箱が通り、木がx方向に無限の広がりを持つ葉を静かに受け取る。その葉はどの覆いとも交わると答えるため、
//! 索引はすべての問い合わせに全件を返しはじめる。
//!
//! 更新の反証では、エラーで返った後の索引が元の場所で元どおりに答えることまで見る。検査を葉の除去より後ろに
//! 置いた実装は、この最後の主張だけで落ちる。

#![allow(clippy::unwrap_used)]

use super::error::動く形の空間索引の操作エラー;
use super::identifier::動く形の識別子;
use super::index::動く形の空間索引;
use super::margin::箱に持たせるゆとりの幅;
use super::sample_fixture::{中心と半分の長さから箱を組む, 端の成分から箱を組む};

// 両端の絶対値の和が倍精度の範囲を出る箱の端であるメートル。和が無限大になり、丸めを包む幅も無限大になる。
const 和が桁あふれする端のメートル: f64 = f64::MAX;
// 両端の絶対値の和が倍精度の範囲に収まる箱の端であるメートル。ゆとりを足した端も有限に収まる。
const 和が収まる端のメートル: f64 = 5.0e307;

fn 既定の幅の索引() -> 動く形の空間索引 {
    動く形の空間索引::ゆとりの幅から生成する(箱に持たせるゆとりの幅::人型と家具の大きさに見合う既定の幅())
}

fn 覆いに出る識別子(索引: &動く形の空間索引, 中心: [f64; 3]) -> Vec<動く形の識別子> {
    let mut 受け皿 = Vec::new();
    索引
        .覆いに触れうる形の識別子を集める(&中心と半分の長さから箱を組む(中心, [0.01, 0.01, 0.01]), &mut 受け皿)
        .unwrap();
    受け皿
}

#[test]
fn 端は有限でもゆとりを足すと桁あふれする箱の登録は型付きエラーで返る() {
    let mut 索引 = 既定の幅の索引();
    let 桁あふれする箱 = 端の成分から箱を組む([-和が桁あふれする端のメートル, -1.0, -1.0], [和が桁あふれする端のメートル, 1.0, 1.0]);
    let 誤り = 索引.形を1つ登録する(動く形の識別子::番号から生成する(1), &桁あふれする箱).unwrap_err();
    assert_eq!(誤り, 動く形の空間索引の操作エラー::ゆとり付きの箱の端が有限でない);
    assert_eq!(索引.登録件数(), 0);
}

#[test]
fn 桁あふれする箱への更新は型付きエラーで返り索引を元のまま残す() {
    let 識別子 = 動く形の識別子::番号から生成する(1);
    let mut 索引 = 既定の幅の索引();
    索引
        .形を1つ登録する(識別子, &中心と半分の長さから箱を組む([0.0, 0.0, 0.0], [1.0, 1.0, 1.0]))
        .unwrap();
    let 桁あふれする箱 = 端の成分から箱を組む([-和が桁あふれする端のメートル, -1.0, -1.0], [和が桁あふれする端のメートル, 1.0, 1.0]);
    let 誤り = 索引.形の箱を更新する(識別子, &桁あふれする箱).unwrap_err();
    assert_eq!(誤り, 動く形の空間索引の操作エラー::ゆとり付きの箱の端が有限でない);
    assert_eq!(索引.登録件数(), 1);
    assert_eq!(覆いに出る識別子(&索引, [0.0, 0.0, 0.0]), vec![識別子]);
    索引.木の不変条件を確かめる();
}

#[test]
fn 和が倍精度に収まる極大の座標の箱は登録を通る() {
    let 識別子 = 動く形の識別子::番号から生成する(1);
    let mut 索引 = 既定の幅の索引();
    let 極大の箱 = 端の成分から箱を組む([-和が収まる端のメートル, -1.0, -1.0], [和が収まる端のメートル, 1.0, 1.0]);
    索引.形を1つ登録する(識別子, &極大の箱).unwrap();
    assert_eq!(索引.登録件数(), 1);
    assert!(索引.ゆとり付きの箱を求める(&極大の箱).相手を丸ごと含むか(&極大の箱));
}
