//! 重なりうる形の対: ゆとり付きの箱どうしが重なった、登録済みの形2つの組である。
//!
//! 触れることが確定した当たりではない。索引が持つのは箱だけであり、しかもその箱は実体より広いゆとり付きの箱で
//! あるから、この対は「実体どうしが重なる可能性が消えていない」ことしか言わない。実体どうしの重なりは形の種類ごとの
//! 詳細判定が答える。剛体の解法は、この対の並びを受け取って詳細判定へ渡す。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断13: 連続衝突と接触点集合を能力として最初から見据える」
//!
//! 2つを識別子の小さい順に並べて持つのは、同じ組が2つの綴りを持たないようにするためである。並べずに持つと、
//! 同じ2つの形について2通りの対が作れ、受け取った側が重複を自分で潰すことになる。
//!
//! 対を組み立てる口はクレートの外へ開かない。利用者が手にするのは列挙が積んだ対だけである。2つが登録済みで
//! 互いに違うことを確かめられるのは形の台帳を持つ索引だけであり、外へ口を開けば、同じ識別子2つの組のように
//! 型の言うことを満たさない値が外から作れてしまう。読み口の2つは、対を受け取った側が中身を見るために開いている。

use super::identifier::動く形の識別子;

/// ゆとり付きの箱どうしが重なった、登録済みの形2つの組。識別子の小さい順に持つ。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 重なりうる形の対 {
    小さいほうの識別子: 動く形の識別子,
    大きいほうの識別子: 動く形の識別子,
}

impl 重なりうる形の対 {
    // 2つの識別子から作る。渡す順に関わらず、小さいほうが先に入る。
    //
    // 注意: この型が言うのは「登録済みで互いに違う形2つの組」であり、それを確かめられるのは形の台帳を持つ索引
    // だけであるから、作る口はクレートの外へ開かない。組を作るのは対の列挙1箇所であり、そこは自分より大きい
    // 識別子の相手だけを採るため、同じ識別子2つがここへ来ることは構造上ない。
    // 参照: `crates/blitz_collision/src/dynamic_index/pair_query.rs`
    pub(super) fn 二つの識別子から生成する(一方: 動く形の識別子, 他方: 動く形の識別子) -> Self {
        Self {
            小さいほうの識別子: 一方.min(他方),
            大きいほうの識別子: 一方.max(他方),
        }
    }

    /// 2つのうち識別子の小さいほう。
    pub fn 小さいほうの識別子(&self) -> 動く形の識別子 {
        self.小さいほうの識別子
    }

    /// 2つのうち識別子の大きいほう。
    pub fn 大きいほうの識別子(&self) -> 動く形の識別子 {
        self.大きいほうの識別子
    }
}
