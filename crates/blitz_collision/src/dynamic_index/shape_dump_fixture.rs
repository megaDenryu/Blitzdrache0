//! 木の形そのものを綴りへ書き出す工程。受け取るのは索引、返すのは節点1つにつき1行の綴りである。
//!
//! 決定性の反証が、同じ操作列を2回流して比べる相手にする。答えの並びだけを比べると、木の形が違っても答えが
//! 同じになる場合を見逃す。書き出すのは深さ・枠の番号・節点の種類・部分木の高さ・葉の識別子・境界の6つの端で
//! あり、枠の番号を入れるのは、取り除いた枠の使い回しまで同じであることを見るためである。

#![cfg(test)]

use blitz_math::大域ワールド位置;

use super::index::動く形の空間索引;
use super::node::{動く形の木の節点の位置, 節点の中身};
use super::tree::動く形の境界箱の木;

impl 動く形の空間索引 {
    pub(super) fn 木の形を綴りへ書き出す(&self) -> String {
        let mut 綴り = String::new();
        if let Some(根) = self.木().根() {
            self.木().節点から下を綴りへ書き足す(根, 0, &mut 綴り);
        }
        綴り
    }
}

impl 動く形の境界箱の木 {
    fn 節点から下を綴りへ書き足す(&self, 位置: 動く形の木の節点の位置, 深さ: usize, 綴り: &mut String) {
        let 節点 = self.節点を読む(位置);
        let 端 = format!("{} {}", 端を綴る(節点.境界().最小の端()), 端を綴る(節点.境界().最大の端()));
        let 枠 = 位置.列の中の位置();
        let 高さ = 節点.部分木の高さ();
        match 節点.中身() {
            節点の中身::葉 { 識別子 } => {
                綴り.push_str(&format!("{深さ} 葉 枠{枠} 高さ{高さ} 識別子{} {端}\n", 識別子.番号()));
            }
            節点の中身::内部 { 子 } => {
                綴り.push_str(&format!("{深さ} 内部 枠{枠} 高さ{高さ} {端}\n"));
                for 子の位置 in 子 {
                    self.節点から下を綴りへ書き足す(子の位置, 深さ + 1, 綴り);
                }
            }
        }
    }
}

fn 端を綴る(端: 大域ワールド位置) -> String {
    format!("({},{},{})", 端.x().値(), 端.y().値(), 端.z().値())
}
