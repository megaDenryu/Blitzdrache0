//! 動く形の境界箱の木: ノードの置き場と根を持ち、葉を1枚挿す操作と1枚外す操作を受け持つ。
//!
//! 呼び出しタイミングは、形を登録したときと、除去したとき、および実体の箱がゆとり付きの箱からはみ出たときである。
//! 形が動いてもゆとりの中に居る間は、この2つの操作をどちらも呼ばない。
//!
//! 不変条件は2つである。(1)内部ノードの境界は2つの子の境界を包む。包む操作は成分の最小と最大を選ぶだけで丸めを
//! 1つも通さないため、この包みは厳密である。(2)根から葉までのどの道も、親の連なりが逆向きに辿れる。葉を挿す
//! ときも外すときも、親の付け替えと子の差し替えを対で行う。
//!
//! 葉を挿すときに新しい内部ノードを1つ作って兄弟の位置へ割り込ませるのは、二分木の形を保つためである。葉を外す
//! ときはその逆で、親を取り除いて兄弟を親の位置へ繰り上げる。したがってノードの総数は葉の数の2倍から1を引いた
//! 数のままである。

use crate::shape::大域の軸平行の直方体;

use super::identifier::動く形の識別子;
use super::node::{動く形の木のノード, 動く形の木のノードの位置};
use super::node_arena::動く形の木のノードの置き場;

mod balance;
mod insertion;
mod links;

pub(super) struct 動く形の境界箱の木 {
    置き場: 動く形の木のノードの置き場,
    根: Option<動く形の木のノードの位置>,
}

impl 動く形の境界箱の木 {
    pub(super) fn 空の木から始める() -> Self {
        Self {
            置き場: 動く形の木のノードの置き場::空の置き場から始める(),
            根: None,
        }
    }

    pub(super) fn 根(&self) -> Option<動く形の木のノードの位置> {
        self.根
    }

    pub(super) fn ノードを読む(&self, 位置: 動く形の木のノードの位置) -> 動く形の木のノード {
        self.置き場.ノードを読む(位置)
    }

    // ゆとり付きの箱を持つ葉を1枚挿し、その位置を返す。木が空なら葉がそのまま根になる。
    pub(super) fn 葉を1枚挿す(&mut self, 識別子: 動く形の識別子, ゆとり付きの箱: 大域の軸平行の直方体) -> 動く形の木のノードの位置 {
        let 葉 = self.置き場.ノードを1つ置く(動く形の木のノード::葉として生成する(ゆとり付きの箱, 識別子));
        let Some(根) = self.根 else {
            self.根 = Some(葉);
            return 葉;
        };
        let 兄弟 = self.挿す先の兄弟を選ぶ(根, &ゆとり付きの箱);
        self.兄弟の位置へ内部ノードを割り込ませる(兄弟, 葉);
        葉
    }

    // 葉を1枚外す。親を取り除いて兄弟を親の位置へ繰り上げ、繰り上げた先から根まで境界と高さを整える。
    pub(super) fn 葉を1枚外す(&mut self, 葉: 動く形の木のノードの位置) {
        let Some(親) = self.ノードを読む(葉).親() else {
            self.根 = None;
            self.置き場.ノードを1つ取り除く(葉);
            return;
        };
        let 兄弟 = self.もう一方の子を求める(親, 葉);
        let 祖父 = self.ノードを読む(親).親();
        self.親を書き換える(兄弟, 祖父);
        match 祖父 {
            Some(祖父の位置) => {
                self.親の子を差し替える(祖父の位置, 親, 兄弟);
                self.高さと境界を根まで整える(祖父の位置);
            }
            None => self.根 = Some(兄弟),
        }
        self.置き場.ノードを1つ取り除く(親);
        self.置き場.ノードを1つ取り除く(葉);
    }

    // 兄弟の居た位置へ新しい内部ノードを割り込ませ、その子を兄弟と葉にする。
    fn 兄弟の位置へ内部ノードを割り込ませる(&mut self, 兄弟: 動く形の木のノードの位置, 葉: 動く形の木のノードの位置) {
        let 兄弟のノード = self.ノードを読む(兄弟);
        let 祖父 = 兄弟のノード.親();
        let 境界 = 兄弟のノード.境界().相手を含む箱を求める(&self.ノードを読む(葉).境界());
        let 新しい親 = self.置き場.ノードを1つ置く(動く形の木のノード::内部として生成する(境界, [兄弟, 葉], 祖父, 兄弟のノード.部分木の高さ() + 1));
        self.親を書き換える(兄弟, Some(新しい親));
        self.親を書き換える(葉, Some(新しい親));
        match 祖父 {
            Some(祖父の位置) => self.親の子を差し替える(祖父の位置, 兄弟, 新しい親),
            None => self.根 = Some(新しい親),
        }
        self.高さと境界を根まで整える(新しい親);
    }
}
