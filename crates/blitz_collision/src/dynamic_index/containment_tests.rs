//! 節点が配下を包む不変条件の反証。登録だけ・登録と除去・登録と更新の3つの操作列で、木の不変条件が破れないことを見る。
//!
//! 3つに分けるのは、木を組み替える経路が3つあるためである。登録は葉を挿す経路、除去は葉を外して兄弟を繰り上げる
//! 経路、更新はその2つを続けて通る経路である。どれか1つで親の付け替えを落とすと、この反証のどれか1つだけが落ちる。

#![allow(clippy::unwrap_used)]

use super::index::動く形の空間索引;
use super::margin::箱に持たせるゆとりの幅;
use super::sample_fixture::{中心と半分の長さから箱を組む, 動く形の見本};

fn 既定の幅の索引() -> 動く形の空間索引 {
    動く形の空間索引::ゆとりの幅から生成する(箱に持たせるゆとりの幅::人型と家具の大きさに見合う既定の幅())
}

#[test]
fn 登録を重ねても節点は配下を包み続ける() {
    let 見本 = 動く形の見本::無作為な箱から作る(200, 11);
    let mut 索引 = 既定の幅の索引();
    for (識別子, 実体の箱) in 見本.一覧() {
        索引.形を1つ登録する(*識別子, 実体の箱).unwrap();
        索引.木の不変条件を確かめる();
    }
    assert_eq!(索引.登録件数(), 200);
}

#[test]
fn 除去を重ねても節点は配下を包み続ける() {
    let 見本 = 動く形の見本::無作為な箱から作る(200, 12);
    let mut 索引 = 既定の幅の索引();
    見本.索引へ登録する(&mut 索引);
    索引.木の不変条件を確かめる();
    for (順番, (識別子, _)) in 見本.一覧().iter().enumerate() {
        if 順番 % 3 == 0 {
            索引.形を1つ除去する(*識別子).unwrap();
            索引.木の不変条件を確かめる();
        }
    }
    assert_eq!(索引.登録件数(), 133);
}

#[test]
fn 箱の更新を重ねても節点は配下を包み続ける() {
    let 見本 = 動く形の見本::無作為な箱から作る(150, 13);
    let mut 索引 = 既定の幅の索引();
    見本.索引へ登録する(&mut 索引);
    for (順番, (識別子, _)) in 見本.一覧().iter().enumerate() {
        let ずらした距離 = f64::from(u32::try_from(順番).unwrap()) * 0.7;
        let 動かした箱 = 中心と半分の長さから箱を組む([ずらした距離, -ずらした距離, 0.5 * ずらした距離], [1.0, 1.0, 1.0]);
        索引.形の箱を更新する(*識別子, &動かした箱).unwrap();
        索引.木の不変条件を確かめる();
    }
    assert_eq!(索引.登録件数(), 150);
}
