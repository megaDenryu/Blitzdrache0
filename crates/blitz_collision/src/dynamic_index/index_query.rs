//! 覆いに触れうる形の識別子を集める工程。受け取るのは覆いと受け皿、返すのは走査が破れたかどうかだけである。
//!
//! 挙げた識別子を呼び出し側の受け皿へ積むのは、1回の問い合わせで確保を起こさないためである。受け皿を使い回せば、
//! 2回目以降の問い合わせは確保を1つもしない。
//!
//! 受け皿を空にするのを入口の最初の1文にするのは、入力の検査より後ろに置くと、型付きエラーで返った問い合わせの
//! 受け皿に前回の候補が残るためである。使い回した受け皿に古い候補が残った状態は、次の問い合わせの結果と
//! 見分けが付かない。
//!
//! 最後に識別子の昇順へ並べ直すのは、答えの並びを木の形から切り離すためである。木の形は登録と除去の順で変わるが、
//! 昇順に並べ直せば、同じ集合を答えるどの木も同じ並びを返す。並べ直しは受け皿の中で行うため確保を起こさない。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断14: 決定性の維持」
//!
//! 覆いの端を丸める操作はここに無い。覆いは呼び出し側が組んだ値をそのまま使い、索引はそれを広げも狭めもしない。
//! 広げた箱を持つのは木の葉の側だけであり、広げる向きは外向きに固定されている。

use crate::shape::大域の軸平行の直方体;

use super::box_edge_check::箱の両端の6成分を軸の順に並べる;
use super::error::動く形の空間索引の問い合わせエラー;
use super::identifier::動く形の識別子;
use super::index::動く形の空間索引;
use super::leaf_scan::覆いに触れる葉の走査;

impl 動く形の空間索引 {
    /// 覆いに触れうる形の識別子を、受け皿へ識別子の昇順で集める。受け皿は、入力を検査するより先に空にする。
    /// 型付きエラーで返るときも空である。
    ///
    /// 挙がるのは候補までである。索引が比べるのは実体より広いゆとり付きの箱であり、覆いに触れているのは
    /// その広げた箱のほうかもしれない。実体との厳密な交差は形の種類ごとの詳細判定が答える。
    pub fn 覆いに触れうる形の識別子を集める(
        &self,
        覆い: &大域の軸平行の直方体,
        受け皿: &mut Vec<動く形の識別子>,
    ) -> Result<(), 動く形の空間索引の問い合わせエラー> {
        受け皿.clear();
        覆いの端が有限であることを確かめる(覆い)?;
        let mut 走査 = 覆いに触れる葉の走査::根から始める(self.木(), *覆い)?;
        while let Some(識別子) = 走査.次の葉の識別子を取り出す()? {
            受け皿.push(識別子);
        }
        受け皿.sort_unstable();
        Ok(())
    }
}

// 覆いの端の6成分が有限であることを確かめる。有限でない端は、どの節点とも交わらない覆いにも、すべての節点と
// 交わる覆いにもなりうる。どちらも答えを静かに間違える。
pub(super) fn 覆いの端が有限であることを確かめる(
    覆い: &大域の軸平行の直方体,
) -> Result<(), 動く形の空間索引の問い合わせエラー> {
    if 箱の両端の6成分を軸の順に並べる(覆い).into_iter().any(|成分| !成分.is_finite()) {
        return Err(動く形の空間索引の問い合わせエラー::覆いの端が有限でない);
    }
    Ok(())
}
