//! 登録済みの形どうしで、ゆとり付きの箱が重なる対を集める工程。受け取るのは受け皿、返すのは走査が破れたかどうかだけである。
//!
//! 辿り方は、識別子の昇順に形を1つ取り、その形のゆとり付きの箱を覆いにして木を1回走査し、自分より大きい識別子の
//! 相手だけを対にする、というものである。自分より大きい相手だけを採るため、同じ対が2度出ない。
//!
//! 2つの木を同時に下る辿り方(節点の対を積んで、交わらない対を捨てながら降りる)を採らないのは、覆いの走査を
//! 1つ持てば対の列挙が同じ辿り方の上に乗るためである。同時に下る方式は、葉の数に比例する回数の根からの下りを
//! 節点の対の走査1回へ畳める代わりに、辿り方をもう1つ持ち込む。どちらを採るかは、対の列挙が予算の主要因に
//! なった日に測って決める。索引の外から見える答えは、どちらの方式でも同じ集合である。
//!
//! 最後に並べ直すのは覆いの問い合わせと同じ理由であり、答えの並びを木の形から切り離すためである。対の順序は
//! 小さいほうの識別子を先に見る辞書式であり、並べ直しは受け皿の中で行うため確保を起こさない。
//! 参照: `crates/blitz_collision/src/dynamic_index/index_query.rs`

use super::error::動く形の空間索引の問い合わせエラー;
use super::index::動く形の空間索引;
use super::leaf_scan::覆いに触れる葉の走査;
use super::pair::重なりうる形の対;

impl 動く形の空間索引 {
    /// 登録済みの形のうち、ゆとり付きの箱どうしが重なる対を受け皿へ集める。並びは、小さいほうの識別子を先に見る
    /// 辞書式の昇順である。受け皿は入口で空にする。
    ///
    /// 挙がるのは候補までである。ゆとり付きの箱が重なっただけであり、実体どうしが重なるかは詳細判定が答える。
    pub fn 重なりうる形の対を集める(
        &self,
        受け皿: &mut Vec<重なりうる形の対>,
    ) -> Result<(), 動く形の空間索引の問い合わせエラー> {
        受け皿.clear();
        for (識別子, 葉の位置) in self.識別子ごとの葉() {
            let 覆い = self.木().節点を読む(*葉の位置).境界();
            let mut 走査 = 覆いに触れる葉の走査::根から始める(self.木(), 覆い)?;
            while let Some(相手の識別子) = 走査.次の葉の識別子を取り出す()? {
                if 相手の識別子 > *識別子 {
                    受け皿.push(重なりうる形の対::二つの識別子から生成する(*識別子, 相手の識別子));
                }
            }
        }
        受け皿.sort_unstable();
        Ok(())
    }
}
