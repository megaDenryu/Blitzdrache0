//! 反証が使う、種から決まった並びを進む擬似乱数。同じ種からは必ず同じ並びが出る。
//!
//! 外部の乱数の実装を持ち込まないのは、反証が落ちたときにどの入力で落ちたかを種だけで再現できるようにするため
//! である。実装は線形合同法であり、統計的な質は要らない。要るのは、箱の位置と大きさを広く散らすことだけである。
//!
//! 生の値を`as`で変換せず、上位24ビットを取り出してから整数の変換で倍精度へ写すのは、数値の`as`キャストが
//! 規約で禁じられているためである。24ビットは倍精度が誤差なく表せる範囲に収まる。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

// 線形合同法の乗数と加数。よく知られた組であり、周期は2の64乗である。
const 乗数: u64 = 6_364_136_223_846_793_005;
const 加数: u64 = 1_442_695_040_888_963_407;

pub(super) struct 決まった種から進む擬似乱数 {
    状態: u64,
}

impl 決まった種から進む擬似乱数 {
    pub(super) fn 種から始める(種: u64) -> Self {
        Self { 状態: 種 }
    }

    // 0以上1未満の値。上位24ビットを2の24乗で割った値である。
    pub(super) fn 次の0以上1未満の値(&mut self) -> f64 {
        self.状態 = self.状態.wrapping_mul(乗数).wrapping_add(加数);
        let 上位24ビット = u32::try_from(self.状態 >> 40).unwrap();
        f64::from(上位24ビット) / 16_777_216.0
    }

    // 下限以上上限未満の値。
    pub(super) fn 範囲の中の値(&mut self, 下限: f64, 上限: f64) -> f64 {
        下限 + (上限 - 下限) * self.次の0以上1未満の値()
    }
}
