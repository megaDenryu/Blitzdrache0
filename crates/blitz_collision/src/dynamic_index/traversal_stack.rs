//! 動く形の木を辿る走査が積む節点の位置のスタック。固定の長さの配列で持ち、確保を1度も起こさない。
//!
//! 上限を128に置く根拠。組み替えは左右の部分木の高さの差を1以内に保つ。高さ h のそういう木が持てる葉の数は
//! 下からフィボナッチ数で押さえられ、高さは葉の数 n について 1.4405·log2(n+2) − 0.3277 以下になる。葉1つにつき
//! 節点はおよそ2つであり、節点1つは境界の箱(48バイト)と中身と親と高さでおよそ80バイトを占めるから、葉の数が
//! メモリに載る限り 2 の 57 乗を越えられない。したがって高さは 84 を越えず、スタックが同時に持つ節点の数は
//! 高さに1を足した数に収まるから、上限128はどの実在しうる木よりも深い木まで辿れる。
//!
//! 高さに1を足した数に収まる根拠は、節点を1つ取り出して2つの子を積む操作が、段ごとに「まだ辿っていない兄弟」を
//! 高々1つしか残さないことである。
//!
//! それでも超過を型付きエラーで返すのは、木が壊れている場合に黙って候補を落とさないためである。

use super::error::動く形の空間索引の問い合わせエラー;
use super::node::動く形の木の節点の位置;

// 同時に積める節点の位置の数。
const 走査のスタックの上限: usize = 128;

pub(super) struct 動く形の木の走査のスタック {
    積んだ位置: [動く形の木の節点の位置; 走査のスタックの上限],
    積んだ数: usize,
}

impl 動く形の木の走査のスタック {
    // 何も積んでいない状態から始める。木が空のときは根が無いため、この状態のまま走査が終わる。
    pub(super) fn 空の状態から始める() -> Self {
        Self {
            積んだ位置: [動く形の木の節点の位置::生成する(0); 走査のスタックの上限],
            積んだ数: 0,
        }
    }

    pub(super) fn 積む(&mut self, 位置: 動く形の木の節点の位置) -> Result<(), 動く形の空間索引の問い合わせエラー> {
        let Some(積む先) = self.積んだ位置.get_mut(self.積んだ数) else {
            return Err(動く形の空間索引の問い合わせエラー::走査のスタックが上限を越えている);
        };
        *積む先 = 位置;
        self.積んだ数 += 1;
        Ok(())
    }

    pub(super) fn 取り出す(&mut self) -> Option<動く形の木の節点の位置> {
        let 取り出す位置 = self.積んだ数.checked_sub(1)?;
        self.積んだ数 = 取り出す位置;
        self.積んだ位置.get(取り出す位置).copied()
    }
}
