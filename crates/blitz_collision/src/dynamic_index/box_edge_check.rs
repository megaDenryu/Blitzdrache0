//! 索引が受け取る実体の箱と、木へ載せるゆとり付きの箱について、端が木へ載せられる値であることを確かめる工程。
//! 受け取るのは箱1つ、返すのは破れた条件である。
//!
//! 検査を実体の箱とゆとり付きの箱の2つに分けるのは、実体の箱の端が有限であっても、ゆとりを足した端が倍精度の
//! 範囲を出うるためである。ゆとりを足す操作は、足す前の両端の絶対値の和に比例した幅を丸めの包みとして一緒に
//! 足す。両端の絶対値が倍精度の最大の桁に近い箱では、この和がまず無限大になり、広げた端が両側とも無限大になる。
//! 実体の箱の端だけを見る検査はこれを通すため、広げた後の端をもう一度見る。
//! 参照: `crates/blitz_collision/src/shape/cover_rounding_margin.rs`
//!
//! 有限でない端を持つ箱を木へ載せると、木はどの覆いとも交わらない箱か、どの覆いとも交わる箱を静かに持つ。
//! どちらも問い合わせの答えを黙って間違える。

use crate::shape::大域の軸平行の直方体;

use super::error::動く形の空間索引の操作エラー;

// 箱の両端の6成分を軸の順に並べる。最小の端の3成分が先、最大の端の3成分が後ろである。端を1成分ずつ見る検査が共有する。
pub(super) fn 箱の両端の6成分を軸の順に並べる(箱: &大域の軸平行の直方体) -> [f64; 6] {
    let 最小 = 箱.最小の端();
    let 最大 = 箱.最大の端();
    [最小.x(), 最小.y(), 最小.z(), 最大.x(), 最大.y(), 最大.z()].map(|成分| 成分.値())
}

// 実体の箱の端が有限で、最小の端が最大の端を越えていないことを確かめる。登録と更新が入口で1度だけ呼ぶ。
pub(super) fn 実体の箱が端を組める値であることを確かめる(
    箱: &大域の軸平行の直方体,
) -> Result<(), 動く形の空間索引の操作エラー> {
    let 端の成分 = 箱の両端の6成分を軸の順に並べる(箱);
    if 端の成分.into_iter().any(|成分| !成分.is_finite()) {
        return Err(動く形の空間索引の操作エラー::実体の箱の端が有限でない);
    }
    if [0usize, 1, 2].into_iter().any(|軸| 端の成分[軸] > 端の成分[軸 + 3]) {
        return Err(動く形の空間索引の操作エラー::実体の箱の最小が最大を越えている);
    }
    Ok(())
}

// 木へ載せるゆとり付きの箱の端が有限であることを確かめる。最小と最大の並びを見ないのは、ゆとりの幅も丸めを包む幅も
// 0以上であり、広げる向きが外側に固定されているため、有限であれば裏返らないからである。
pub(super) fn ゆとり付きの箱の端が有限であることを確かめる(
    箱: &大域の軸平行の直方体,
) -> Result<(), 動く形の空間索引の操作エラー> {
    if 箱の両端の6成分を軸の順に並べる(箱).into_iter().any(|成分| !成分.is_finite()) {
        return Err(動く形の空間索引の操作エラー::ゆとり付きの箱の端が有限でない);
    }
    Ok(())
}
