//! 三角形のカプセルの掃引の問い合わせ: カプセルを変位の分だけ動かそうとしたとき、三角形に触れるまでに
//! どこまで動けるかを求める操作サービス。三角形の線分の問い合わせをコンストラクタで組んで保持するため、
//! 問い合わせの署名に形が現れない。面の単位法線は線分の問い合わせが持つ面の向きを備えた三角形から読む。
//!
//! 線分の問い合わせを保持するのは、掃引の始まりでカプセルの軸そのものが三角形を貫いているかという問いが、
//! 軸の線分が三角形に当たるかという問いと同じものだからである。その判定は`sweep_start_overlap.rs`が担う。
//!
//! 1回の問い合わせでヒープを確保しない。持つのは特徴ごとの最小の候補1つだけである。
//!
//! 接触の単位法線を単精度へ狭めるのはここ1箇所である。20通りの候補それぞれで平方根と割り算を通すのを避けるため、
//! 求解は接触位置から軸へ向かう倍精度の変位のまま持ち回り、最小の候補が決まってから正して狭める。
//!
//! 面の向きを備えた三角形を受け取る入口を別に持つのは、三角形網が三角形ごとの面の向きを保持しており、
//! 候補1枚ごとに外積と平方根を通し直さないためである。

use blitz_math::{ローカル, 方向};

use crate::shape::{局所座標の三角形, 形の局所座標の変位, 形を掃引するカプセル, 面の向きを備えた三角形};
use crate::solver::掃引で動けた割合;

use super::error::三角形の問い合わせエラー;
use super::segment_query::三角形の線分の問い合わせ;
use super::sweep_contact::{カプセルが三角形に最初に触れる点, 掃引したカプセルの三角形への接触};
use super::sweep_place::三角形で触れた場所;
use super::sweep_solver::カプセルと三角形の接触の求解;

/// 一般の三角形のカプセルの掃引の問い合わせ。三角形の線分の問い合わせを保持し、掃引の接触を答える操作サービスである。
pub struct 三角形のカプセルの掃引の問い合わせ {
    線分の問い合わせ: 三角形の線分の問い合わせ,
}

impl 三角形のカプセルの掃引の問い合わせ {
    /// 三角形の線分の問い合わせを組んで保持する。面の向きを求める外積と平方根はこの生成の1回だけ通る。
    /// 面積が零の三角形は平面も向きも定まらないため、型付きエラーで拒む。
    pub fn 三角形から生成する(三角形: 局所座標の三角形) -> Result<Self, 三角形の問い合わせエラー> {
        Ok(Self {
            線分の問い合わせ: 三角形の線分の問い合わせ::三角形から生成する(三角形)?,
        })
    }

    /// 面の向きを既に備えた三角形から組む。三角形網が三角形ごとの面の向きを持っており、候補1枚ごとに
    /// 外積と平方根を通し直さないための入口である。向きが定まっていることは受け取る型が保証する。
    pub fn 面の向きを備えた三角形から生成する(三角形: 面の向きを備えた三角形) -> Self {
        Self {
            線分の問い合わせ: 三角形の線分の問い合わせ::面の向きを備えた三角形から生成する(三角形),
        }
    }

    /// カプセルが三角形に最初に触れる点を求める。掃引の始まりで既に半径以内に居てそこへ向かうカプセルは、動けた割合0で返す。
    /// 面から離れる変位と平行な変位では始まりの接触を持たず、途中で触れ始める接触だけを答える。
    pub fn カプセルが三角形に最初に触れる点を求める(
        &self,
        カプセル: &形を掃引するカプセル,
    ) -> Result<カプセルが三角形に最初に触れる点, 三角形の問い合わせエラー> {
        let 求解 = カプセルと三角形の接触の求解::生成する(カプセル, self.線分の問い合わせ.三角形());
        if let Some(場所) = self.掃引の始まりで触れている場所を求める(カプセル, &求解)? {
            let 接触 = self.接触を組む(掃引で動けた割合::一歩も動けなかった(), 場所)?;
            return Ok(カプセルが三角形に最初に触れる点::三角形に触れる(接触));
        }
        match 求解.掃引の途中で最初に触れる接触を求める()? {
            Some(触れ始める) => Ok(カプセルが三角形に最初に触れる点::三角形に触れる(
                self.接触を組む(触れ始める.動けた割合(), 触れ始める.場所())?,
            )),
            None => Ok(カプセルが三角形に最初に触れる点::三角形に触れない),
        }
    }

    // 保持している線分の問い合わせと面の単位法線。掃引の始まりの重なりを見る工程が読む。
    pub(super) fn 線分の問い合わせ(&self) -> &三角形の線分の問い合わせ {
        &self.線分の問い合わせ
    }

    pub(super) fn 面の単位法線の変位(&self) -> 形の局所座標の変位 {
        self.線分の問い合わせ.三角形().単位法線の変位()
    }

    // 触れた場所から答えを組む。接触位置から軸へ向かう変位を長さ1に正した向きが接触の単位法線であり、
    // 長さが0で向きが定まらないときは面の単位法線を使う。
    fn 接触を組む(
        &self,
        動けた割合: 掃引で動けた割合,
        場所: 三角形で触れた場所,
    ) -> Result<掃引したカプセルの三角形への接触, 三角形の問い合わせエラー> {
        let 単位法線 = match 場所.接触位置から軸への変位().長さで正した方向へ狭める() {
            Some(結果) => 結果?,
            None => self.面の単位法線を狭める()?,
        };
        Ok(掃引したカプセルの三角形への接触::生成する(
            動けた割合,
            場所.接触位置(),
            単位法線,
            場所.触れた特徴(),
        ))
    }

    fn 面の単位法線を狭める(&self) -> Result<方向<ローカル>, 三角形の問い合わせエラー> {
        match self.面の単位法線の変位().長さで正した方向へ狭める() {
            Some(結果) => Ok(結果?),
            None => Err(三角形の問い合わせエラー::接触の単位法線が定まらない),
        }
    }
}
