//! 線分と三角形の平面の関係: 線分の両端の平面までの隔たりから、平面を横切るか・平面の中を走るか・平面へ
//! 届かないかを見分けた結果である。受け取るのは両端の隔たり、返すのはこの3つの枝である。
//!
//! 同じ側に在ることを2つの隔たりの積で見ないのは、どちらも極めて小さい同符号の値のとき積が零へ丸められ、
//! 同じ側なのに同じ側でないと読めるためである。10のマイナス200乗の桁の隔たりが2つあると積は10の
//! マイナス400乗となり、倍精度の表せる最小の値を下回って零になる。そのとき求解は平面を横切る側へ入り、
//! 負の媒介変数を端へ寄せた偽の当たりを返す。符号を1つずつ比べれば、隔たりの桁に依らず同じ側かどうかが決まる。
//!
//! 零の扱いを明示する。零は平面の上であり、正の側にも負の側にも属さないため同じ側とは数えない。したがって
//! 片方だけが零の線分は平面を横切る側へ入り、媒介変数0または1の当たりになる。両方が零の線分だけが平面の
//! 中を走る枝になる。有限でない隔たりも同じ側と数えず、横切る側の割り算が有限でない媒介変数を導いて
//! 型付きエラーで拒まれる形に残す。
//!
//! 平面の中を走る枝を平面へ届かない枝と分けるのは、平面の中でも三角形の外から辺へ入る線分には最初の交点が
//! 定義できるためである。その交点を求めるのは`crates/blitz_collision/src/triangle/segment_in_plane.rs`である。

/// 線分と三角形の平面の関係。
pub(super) enum 線分と三角形の平面の関係 {
    /// 両端が平面の同じ側に在るか、平面と平行で平面から離れている。
    平面へ届かない,
    /// 両端がどちらも平面の上に在り、線分の全体が平面の中を走る。
    平面の中を走る,
    /// 平面を横切り、横切る媒介変数が定まる。
    平面を横切る {
        /// 線分の始点を0、終点を1として測った、平面を横切る媒介変数。丸めで0や1をわずかに外れうる。
        横切る媒介変数: f64,
    },
}

impl 線分と三角形の平面の関係 {
    pub(super) fn 両端の隔たりから見分ける(始点の隔たり: f64, 終点の隔たり: f64) -> Self {
        if 始点の隔たり == 0.0 && 終点の隔たり == 0.0 {
            return Self::平面の中を走る;
        }
        if 両端が平面の同じ側に在るか(始点の隔たり, 終点の隔たり) {
            return Self::平面へ届かない;
        }
        let 隔たりの差 = 始点の隔たり - 終点の隔たり;
        if 隔たりの差 == 0.0 {
            return Self::平面へ届かない;
        }
        Self::平面を横切る {
            横切る媒介変数: 始点の隔たり / 隔たりの差,
        }
    }
}

// 両端が平面の同じ側に在るか。積を作らず0との大小を隔たりごとに見るため、隔たりがどれだけ小さくても
// 判定が桁落ちで変わらない。零も有限でない値もどちらの比較にも合わないため、同じ側とは数えない。
fn 両端が平面の同じ側に在るか(始点の隔たり: f64, 終点の隔たり: f64) -> bool {
    let 両方が正 = 始点の隔たり > 0.0 && 終点の隔たり > 0.0;
    let 両方が負 = 始点の隔たり < 0.0 && 終点の隔たり < 0.0;
    両方が正 || 両方が負
}
