//! 線分と三角形の平面の関わりの判定。受け取るのは線分、返すのは平面に載っているか・平面と平行で離れているか・
//! 平面を横切る向きであるかの3つの区別である。線分の当たりの3つの解き方は、この区別1つで分かれる。
//!
//! 区別を剪断で写した辺の面積の総和でなく両端の平面までの隔たりで行うのは、隔たりが剪断を1つも通らない量だから
//! である。写した面積は線分の向きが決める剪断の係数を含み、係数が3分の2のように2進で表せない向きでは、平面に
//! 載る線分でも3つの面積が零へ揃わない。総和が零かで判ずると、正負の混じった面積が「三角形の外を通る」と先に
//! 答え、平面の中を走る線分の解き方へ入る前に当たりが消える。
//! 参照: `crates/blitz_collision/src/triangle/segment_tilted_plane_tests.rs`
//!
//! 判ずる順序は、平面に載るかを先に、平面と平行かを後に見る。両端の隔たりが等しいことが向きの平行を意味し、
//! 両端がともに零である平面の中の線分もその等しい場合に含まれるためである。
//!
//! 始点と終点が同じ線分もこの判定で正しく分かれる。両端の隔たりが必ず等しくなるため、平面の上の1点なら
//! 平面に載っている、平面から離れた1点なら平面と平行で離れているになる。

use crate::shape::形を貫く線分;

use super::segment_query::三角形の線分の問い合わせ;

// 線分と三角形の平面の関わり。線分がその平面と1点も交わらないか、平面の中を走るか、平面を1点で貫くかを分ける。
pub(super) enum 線分と平面の関わり {
    平面に載っている,
    平面と平行で離れている,
    平面を横切る向きである,
}

impl 三角形の線分の問い合わせ {
    // 線分と三角形の平面の関わりを両端の隔たりから判ずる。隔たりは面に垂直な変位で測るため長さの単位ではないが、
    // 零であるかと2つが等しいかしか読まないため、単位のある量へ直す必要が無い。
    pub(super) fn 線分と平面の関わりを判ずる(&self, 線分: &形を貫く線分) -> 線分と平面の関わり {
        let 始点の隔たり = self.点から平面までの隔たりを求める(線分.始点());
        let 終点の隔たり = self.点から平面までの隔たりを求める(線分.終点());
        if 始点の隔たり == 0.0 && 終点の隔たり == 0.0 {
            return 線分と平面の関わり::平面に載っている;
        }
        if 始点の隔たり == 終点の隔たり {
            return 線分と平面の関わり::平面と平行で離れている;
        }
        線分と平面の関わり::平面を横切る向きである
    }
}
