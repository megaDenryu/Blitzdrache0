//! 三角形への問い合わせの反証が共有する材料。三角形と線分を組む道具と、答えを人が読める組へ落とす読み取りを持つ。
//! 掃引の入口は`sweep_fixture.rs`が別に持つ。
//!
//! 見本の三角形を水平な直角三角形に固定するのは、期待値の手計算がこの1つの形を前提に書かれているためである。
//! 頂点を(0,0,0)・(4,0,0)・(0,0,4)に取ると、面に垂直な変位が天頂の負の向きの長さ16の変位になり、平面までの
//! 隔たりが割り切れる十進の値で読める。頂点の並びが天頂の負の向きを表にするのは、両面から当たることを反証で
//! 見るために、表と裏のどちらから来たかで答えが変わることを確かめたいからである。

use blitz_math::{ローカル, 方向};

use crate::shape::{局所座標の三角形, 形の局所座標の位置};

use super::segment::三角形を貫く線分;
use super::segment_hit::{三角形への最初の当たり, 線分が三角形に最初に当たる点};
use super::segment_query::三角形の線分の問い合わせ;

pub(super) fn 局所の点(成分: [f64; 3]) -> 形の局所座標の位置 {
    match 形の局所座標の位置::生成する(成分[0], 成分[1], 成分[2]) {
        Ok(位置) => 位置,
        Err(誤り) => panic!("試験用の局所の点を作れなかった: {誤り}"),
    }
}

pub(super) fn 三角形を作る(頂点: [[f64; 3]; 3]) -> 局所座標の三角形 {
    局所座標の三角形::三つの頂点から生成する(頂点.map(局所の点))
}

pub(super) fn 水平な直角三角形() -> 局所座標の三角形 {
    三角形を作る([[0.0, 0.0, 0.0], [4.0, 0.0, 0.0], [0.0, 0.0, 4.0]])
}

pub(super) fn 線分を作る(始点: [f64; 3], 終点: [f64; 3]) -> 三角形を貫く線分 {
    三角形を貫く線分::生成する(局所の点(始点), 局所の点(終点))
}

pub(super) fn 見本の三角形への線分の当たりを求める(
    始点: [f64; 3], 終点: [f64; 3]
) -> 線分が三角形に最初に当たる点 {
    let 問い合わせ = match 三角形の線分の問い合わせ::三角形から生成する(水平な直角三角形()) {
        Ok(問い合わせ) => 問い合わせ,
        Err(誤り) => panic!("試験用の三角形の問い合わせを作れなかった: {誤り}"),
    };
    match 問い合わせ.線分が三角形に最初に当たる点を求める(&線分を作る(始点, 終点)) {
        Ok(答え) => 答え,
        Err(誤り) => panic!("線分の問い合わせが失敗した: {誤り}"),
    }
}

pub(super) fn 線分の当たりを取り出す(答え: 線分が三角形に最初に当たる点) -> 三角形への最初の当たり {
    match 答え {
        線分が三角形に最初に当たる点::三角形に当たる(当たり) => 当たり,
        線分が三角形に最初に当たる点::三角形に当たらない => panic!("当たるはずの線分が当たらなかった"),
    }
}

pub(super) fn 位置の成分(位置: 形の局所座標の位置) -> [f64; 3] {
    [位置.xのメートル(), 位置.yのメートル(), 位置.zのメートル()]
}

/// 3成分が期待値から許容の幅の中に在ることを確かめる。掃引の根が2進で割り切れない組では、時刻から位置を
/// 組み直す演算が厳密には元の値へ戻らない。
pub(super) fn 三成分が近いことを確かめる(実測: [f64; 3], 期待: [f64; 3], 許容: f64, 何の値か: &str) {
    for 軸 in 0usize..3 {
        assert!(
            (実測[軸] - 期待[軸]).abs() <= 許容,
            "{何の値か}の軸{軸}が期待から離れている(実測{}、期待{})",
            実測[軸],
            期待[軸]
        );
    }
}

pub(super) fn 方向の成分(方向: 方向<ローカル>) -> [f32; 3] {
    [方向.x(), 方向.y(), 方向.z()]
}
