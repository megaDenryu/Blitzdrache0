//! 平面の上の点が三角形のどの特徴に載っているかを決める工程。受け取るのは辺ごとの符号、返すのは当たった特徴
//! である。どれか1つでも負なら三角形の外であり、特徴を持たない。
//!
//! 零になった辺の並びが特徴を決める。零が無ければ面の内側、1つなら その辺の上、2つならその2辺が共有する頂点で
//! ある。辺は頂点の番号1つで指し、番号の頂点から次の番号の頂点へ張る。したがって辺の並びの位置iと位置i+1が
//! 共有する頂点は、番号i+1の頂点である。
//!
//! 等号を丸めた値どうしの厳密な比較で見るのは、近い値を同じとみなす幅を置くと、幅の中の位置で答えが面と辺の
//! 間を揺れるためである。任意姿勢の直方体の線分の交差が、板の境界へ達する時刻の等号を厳密に見るのと同じ
//! 規律である(`crates/blitz_collision/src/oriented_box/segment_entry.rs`)。

use crate::shape::三角形の頂点の番号;

use super::feature::三角形で当たった特徴;

// 辺ごとの符号から、点が載る特徴を決める。3辺のどれかについて負なら三角形の外であるため値なしを返す。
pub(super) fn 点が載る特徴を求める(辺ごとの符号: [f64; 3]) -> Option<三角形で当たった特徴> {
    if 辺ごとの符号.into_iter().any(|符号| 符号 < 0.0) {
        return None;
    }
    Some(零になった辺の並びから特徴を組む(辺ごとの符号.map(|符号| 符号 == 0.0)))
}

// 3辺のうちどれが零になったかの並びから特徴を組む。3つとも零になるのは、面積が零の三角形か、辺と点の外積が
// 零へ落ちるほど小さい三角形だけである。前者は問い合わせの生成が拒み、後者では3つの特徴がどれも同じ点を
// 指すため、面として答える。
fn 零になった辺の並びから特徴を組む(零になったか: [bool; 3]) -> 三角形で当たった特徴 {
    match 零になったか {
        [false, false, false] | [true, true, true] => 三角形で当たった特徴::三角形の面,
        [true, false, false] => 辺の上として組む(三角形の頂点の番号::第1の頂点),
        [false, true, false] => 辺の上として組む(三角形の頂点の番号::第2の頂点),
        [false, false, true] => 辺の上として組む(三角形の頂点の番号::第3の頂点),
        [true, true, false] => 三角形で当たった特徴::三角形の頂点(三角形の頂点の番号::第2の頂点),
        [false, true, true] => 三角形で当たった特徴::三角形の頂点(三角形の頂点の番号::第3の頂点),
        [true, false, true] => 三角形で当たった特徴::三角形の頂点(三角形の頂点の番号::第1の頂点),
    }
}

fn 辺の上として組む(始まりの頂点: 三角形の頂点の番号) -> 三角形で当たった特徴 {
    三角形で当たった特徴::三角形の辺 { 始まりの頂点 }
}
