//! 三角形の辺の内側と軸の内側の接触。ねじれの位置にある2直線どうしが半径だけ離れて並ぶ時刻を解く。
//!
//! 2直線の隔たりは、両方に垂直な向き(2つの変位の外積)へ射影した長さである。射影は時刻の1次式であるから、
//! 隔たりが半径に等しくなる時刻も1次で決まる。2乗した形で解くのは、カプセルが辺のどちら側から来ても
//! 同じ1つの式で扱うためである。2つの直線が平行なとき外積は零になり、隔たりが定まらないためこの候補を数えない。
//! 平行な場合の最も早い接触は、軸の端か辺の端すなわち三角形の頂点の候補が同じ時刻で答える。
//!
//! 直線は辺と軸より長いため、根の時刻で2つの最近接点がそれぞれ辺と軸の内側に収まることを確かめる。
//!
//! 掃引の5種類の候補のうち、係数が最も大きく育つのはこの式である。内積の相手が変位そのものでなく2つの変位の
//! 外積であるため、そのぶん次数が2つ上がる。桁あふれしないことの算術は `crates/blitz_collision/src/triangle.rs`
//! にある。

use crate::shape::三角形の頂点の番号;
use crate::solver::二つの直線の最近接の媒介変数;
use crate::solver::掃引の2次方程式;
use crate::solver::軸の端;

use super::error::三角形の問い合わせエラー;
use super::sweep_place::軸と特徴の最近接;
use super::sweep_solver::カプセルと三角形の接触の求解;

impl カプセルと三角形の接触の求解<'_> {
    pub(super) fn 辺と軸の内側の方程式を組む(&self, 始まりの頂点: 三角形の頂点の番号) -> Option<掃引の2次方程式> {
        掃引の2次方程式::二つの直線の隔たりから組む(
            self.頂点から時刻の軸の端への変位(始まりの頂点, 軸の端::始点の側, 0.0),
            self.掃引の変位(),
            self.軸の変位(),
            self.三角形().辺の変位を求める(始まりの頂点),
            self.半径の二乗(),
        )
    }

    // 時刻での、辺の直線と軸の直線の最近接。どちらかの最近接点がその範囲の外にあるなら値なしを返す。
    pub(super) fn 辺と軸の内側の最近接を求める(
        &self,
        始まりの頂点: 三角形の頂点の番号,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, 三角形の問い合わせエラー> {
        let 軸 = self.軸の変位();
        let 辺の変位 = self.三角形().辺の変位を求める(始まりの頂点);
        let 辺の始点から軸の始点へ = self.頂点から時刻の軸の端への変位(始まりの頂点, 軸の端::始点の側, 時刻);
        let Some(媒介変数) =
            二つの直線の最近接の媒介変数::両方の範囲に収まる組を求める(軸, 辺の変位, 辺の始点から軸の始点へ)
        else {
            return Ok(None);
        };
        let 接触点から軸へ = 辺の始点から軸の始点へ
            .加える(軸.実数倍する(媒介変数.第1の直線の比()))
            .引く(辺の変位.実数倍する(媒介変数.第2の直線の比()));
        Ok(Some(self.辺に触れた最近接を組む(
            始まりの頂点,
            媒介変数.第2の直線の比(),
            接触点から軸へ,
        )?))
    }
}
