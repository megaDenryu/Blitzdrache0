//! 線分の枠へ写した三角形: 3つの頂点を線分に合わせた剪断の座標枠で写した座標と、そこから求めた辺ごとの符号付き
//! 面積を1つにまとめたものである。受け取るのは枠と三角形、返すのは線分が三角形の中を通るか・いつ通るか・どの特徴を
//! 踏むかを決める材料である。
//!
//! 辺ごとの符号付き面積とは、線分が通る原点と辺の2つの端が作る三角形の、写した面での符号付き面積のことである。
//! 並びは`辺ごとの符号を求める`と同じく、番号の頂点から次の番号の頂点へ張る辺の順である。3つが同じ符号(零を許す)
//! なら原点は三角形の中に在り、負のものと正のものが混じっていれば外に在る。零になった辺は、その辺の直線の上を
//! 線分が通ることを意味する。
//!
//! 隣り合う2枚が共有する辺について、この量は符号の反転そのものになる。理由は3つの重なりである。第1に、写しは
//! 三角形でなく線分から決まるため、2枚は共有辺の2つの端についてビット単位で同じ座標を持つ。第2に、一方の枚は端を
//! (始まり,終わり)の順に、他方の枚は(終わり,始まり)の順に掛け合わせるため、式は掛ける順序だけが違う2つの積の差に
//! なる。第3に、倍精度の掛け算は順序を変えても同じ値であり、引き算は左右を入れ替えると符号だけが反転する。
//! したがって一方が正なら他方は必ず負であり、丸めで両方が負に出て2枚とも「外」と答える割れが構造的に起きない。
//!
//! 頂点の重心座標は、その頂点の向かい側の辺の面積を3つの面積の総和で割ったものである。総和は写した三角形の
//! 符号付き面積の2倍にあたり、線分が三角形の平面に載るとつぶれて零になる。

use crate::shape::{三角形の頂点の番号, 面の向きを備えた三角形};

use super::segment_shear_frame::線分に合わせた剪断の座標枠;
use super::sheared_vertex::線分の枠へ写した頂点;

pub(super) struct 線分の枠へ写した三角形 {
    写した頂点: [線分の枠へ写した頂点; 3],
    辺ごとの符号付き面積: [f64; 3],
    面積の総和: f64,
}

impl 線分の枠へ写した三角形 {
    pub(super) fn 枠で写して組む(枠: &線分に合わせた剪断の座標枠, 三角形: &面の向きを備えた三角形) -> Self {
        let 写した頂点 = 三角形の頂点の番号::並べる().map(|番号| 枠.頂点を写す(三角形.頂点の位置(番号)));
        let 辺ごとの符号付き面積 = 三角形の頂点の番号::並べる().map(|番号| {
            let 始まり = 写した頂点[番号.並びの位置()];
            let 終わり = 写した頂点[番号.次の頂点().並びの位置()];
            終わり.横の座標() * 始まり.縦の座標() - 終わり.縦の座標() * 始まり.横の座標()
        });
        Self {
            写した頂点,
            辺ごとの符号付き面積,
            面積の総和: 辺ごとの符号付き面積.into_iter().sum(),
        }
    }

    // 線分が三角形の外を通るか。辺ごとの面積に負のものと正のものが混じっていれば外である。
    pub(super) fn 線分が三角形の外を通るか(&self) -> bool {
        let 負がある = self.辺ごとの符号付き面積.into_iter().any(|面積| 面積 < 0.0);
        let 正がある = self.辺ごとの符号付き面積.into_iter().any(|面積| 面積 > 0.0);
        負がある && 正がある
    }

    // 辺ごとの面積の総和。重心座標と交差の時刻の分母であり、零なら線分が三角形の平面に載っている。
    pub(super) fn 面積の総和(&self) -> f64 {
        self.面積の総和
    }

    // 交差の時刻の分子。頂点ごとの重みへその頂点の媒介変数の座標を掛けて足したものであり、総和で割ると時刻になる。
    // 重みを先に割らないのは、割り算を最後の1回だけにして丸めを1つに抑えるためである。
    pub(super) fn 交差の時刻の分子を求める(&self) -> f64 {
        三角形の頂点の番号::並べる()
            .into_iter()
            .map(|番号| self.頂点の重みを求める(番号) * self.写した頂点[番号.並びの位置()].媒介変数の座標())
            .sum()
    }

    // 番号の頂点の重心座標。重みを総和で割ったものであり、3つを足すと1になる。
    pub(super) fn 頂点の重心座標を求める(&self, 番号: 三角形の頂点の番号) -> f64 {
        self.頂点の重みを求める(番号) / self.面積の総和
    }

    // 面積が零になった辺の並び。零の並びが当たった特徴(面・辺・頂点)を決める。
    pub(super) fn 零になった辺の並びを求める(&self) -> [bool; 3] {
        self.辺ごとの符号付き面積.map(|面積| 面積 == 0.0)
    }

    // 番号の頂点の重み。向かい側の辺、すなわち次の番号の頂点から張る辺の面積である。
    fn 頂点の重みを求める(&self, 番号: 三角形の頂点の番号) -> f64 {
        self.辺ごとの符号付き面積[番号.次の頂点().並びの位置()]
    }
}
