//! 線分に合わせた剪断の座標枠: 線分の向きから決まる3本の軸の割り当てと剪断の係数を、線分1本につき1度だけ
//! 組んだものである。受け取るのは三角形の頂点、返すのはその頂点を線分が真っ直ぐ立つ向きへ剪断して写した座標である。
//!
//! 三角形ごとでなく線分ごとに組むのが要点である。隣り合う2枚が共有する辺の上の点を、2枚がまったく同じ写しの上で
//! 評価するため、共有辺について2枚が出す量が符号の反転そのものになる。写しを三角形ごとに組むと、同じ辺を別々の
//! 座標で見ることになり、2枚がともに「外」と答える取り逃しが起きる。
//! 参照: `crates/blitz_collision/src/triangle/sheared_triangle.rs`
//!
//! 向きの絶対値が最も大きい軸を線分に沿わせる軸に選ぶのは、剪断の係数の分母をその成分にするためである。残る2本の
//! 成分を最も大きい成分で割るため、係数の絶対値は1以下に収まり、剪断が値の桁を増やさない。
//!
//! 沿わせる軸の成分が負のときに横と縦を入れ替えるのは、写した面での三角形の回り方(3頂点が右回りか左回りか)を
//! 保つためである。入れ替えないと、線分がその軸の負の向きへ進むときだけ写した三角形が裏返る。
//!
//! 方式の出どころは Woop・Benthin・Wald 2013 の水密な線分と三角形の交差である。

use crate::shape::{形の局所座標の位置, 形の局所座標の軸, 形を貫く線分};

use super::sheared_vertex::線分の枠へ写した頂点;

pub(super) struct 線分に合わせた剪断の座標枠 {
    線分の始点: 形の局所座標の位置,
    写した面の横の軸: 形の局所座標の軸,
    写した面の縦の軸: 形の局所座標の軸,
    線分に沿わせる軸: 形の局所座標の軸,
    横の軸の剪断の係数: f64,
    縦の軸の剪断の係数: f64,
    沿わせる軸の成分を媒介変数へ直す率: f64,
}

impl 線分に合わせた剪断の座標枠 {
    // 線分から組む。始点と終点が同じで向きが定まらない線分では値なしを返す。
    pub(super) fn 線分から生成する(線分: &形を貫く線分) -> Option<Self> {
        let 向き = 線分.始点から終点への変位を求める();
        let 沿わせる軸 = 向き.絶対値が最も大きい軸を求める()?;
        let 沿わせる成分 = 向き.軸に沿ったメートル(沿わせる軸);
        let (次の軸, その次の軸) = (沿わせる軸.次の軸(), 沿わせる軸.次の軸().次の軸());
        let (横の軸, 縦の軸) = if 沿わせる成分 < 0.0 {
            (その次の軸, 次の軸)
        } else {
            (次の軸, その次の軸)
        };
        Some(Self {
            線分の始点: 線分.始点(),
            写した面の横の軸: 横の軸,
            写した面の縦の軸: 縦の軸,
            線分に沿わせる軸: 沿わせる軸,
            横の軸の剪断の係数: 向き.軸に沿ったメートル(横の軸) / 沿わせる成分,
            縦の軸の剪断の係数: 向き.軸に沿ったメートル(縦の軸) / 沿わせる成分,
            沿わせる軸の成分を媒介変数へ直す率: 1.0 / 沿わせる成分,
        })
    }

    // 三角形の頂点をこの枠へ写す。線分の始点を原点へ動かしてから、線分が横も縦も零の直線になるように剪断する。
    pub(super) fn 頂点を写す(&self, 頂点: 形の局所座標の位置) -> 線分の枠へ写した頂点 {
        let 始点からの変位 = self.線分の始点.終点までの変位を求める(頂点);
        let 沿わせる軸の成分 = 始点からの変位.軸に沿ったメートル(self.線分に沿わせる軸);
        線分の枠へ写した頂点::三つの座標から組む(
            始点からの変位.軸に沿ったメートル(self.写した面の横の軸) - self.横の軸の剪断の係数 * 沿わせる軸の成分,
            始点からの変位.軸に沿ったメートル(self.写した面の縦の軸) - self.縦の軸の剪断の係数 * 沿わせる軸の成分,
            self.沿わせる軸の成分を媒介変数へ直す率 * 沿わせる軸の成分,
        )
    }
}
