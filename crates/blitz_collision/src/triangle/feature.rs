//! 三角形で当たった特徴: 線分またはカプセルが三角形のどの部分に当たったかである。面・3辺・3頂点を区別する。
//!
//! 区別を残すのは、接触の単位法線の出どころが3つで違うためである。面に当たったときの法線は三角形の面の
//! 単位法線そのものであり、辺と頂点に触れたときの法線は接触点からカプセルの軸へ向かう向きである。
//!
//! 辺を頂点の番号1つで指すのは、その頂点から次の番号の頂点へ張ったものが辺だからである。辺に別の番号を与えると、
//! 頂点の番号と辺の番号の対応を呼び出し側が別の決まりで覚えることになる。
//!
//! 網の中では隣り合う三角形が辺と頂点を共有するため、同じ幾何の特徴が別の三角形の番号で返ることがある。
//! どちらの名前も同じ点を指しており、接触の位置は一致する。法線は三角形ごとに違う。

use crate::shape::三角形の頂点の番号;

/// 線分またはカプセルが三角形のどの部分に当たったか。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum 三角形で当たった特徴 {
    /// 面の内側に当たった。
    三角形の面,
    /// 辺の上に当たった。
    三角形の辺 {
        /// 辺の始まりになる頂点の番号。辺はこの頂点から次の番号の頂点へ張る。
        始まりの頂点: 三角形の頂点の番号,
    },
    /// 頂点そのものに当たった。
    三角形の頂点(三角形の頂点の番号),
}
