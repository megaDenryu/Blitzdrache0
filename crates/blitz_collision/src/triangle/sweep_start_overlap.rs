//! 掃引の始まりで、カプセルが既に三角形へ触れているかを見る工程。受け取るのはカプセルと接触の求解、返すのは
//! 触れているならその場所である。触れていなければ値なしを返し、呼び出し側は掃引の途中の接触を解きにいく。
//!
//! 掃引の主経路(`sweep_query.rs`)と別に置くのは、これが掃引の時刻を1つも解かない別の工程だからである。
//! 見るのは時刻0の姿勢だけであり、2次方程式も根も出てこない。
//!
//! 軸そのものが三角形を貫いているかを、特徴ごとの最近接より先に見る。貫いていれば軸から三角形までの隔たりは
//! 0であるが、特徴ごとの最近接をいくら数えてもその0には達しない。軸の両端も辺も頂点も面から離れているためである。
//!
//! 貫いた場合に押し戻す向きはこの層では決まらない。軸の両側に面があり、どちらへ押し戻すのが近いかを決める材料を
//! この層が持たないためである。軸の始点が在る側を向く面の単位法線を返す。高さ場の掃引が上向きの単位法線を返した
//! 妥協と同じ様式である。

use crate::shape::{三角形の頂点の番号, 形の局所座標の変位, 形を掃引するカプセル, 形を貫く線分};

use super::error::三角形の問い合わせエラー;
use super::segment_hit::線分が三角形に最初に当たる点;
use super::sweep_place::三角形で触れた場所;
use super::sweep_query::三角形のカプセルの掃引の問い合わせ;
use super::sweep_solver::カプセルと三角形の接触の求解;

impl 三角形のカプセルの掃引の問い合わせ {
    // 掃引の始まりで既に触れていて掃引がそこへ向かうなら、その場所。軸が三角形を貫く場合を先に見て、
    // 次に特徴ごとの最近接を半径と比べる。面から離れる変位と平行な変位では触れていないものとして扱う。
    pub(super) fn 掃引の始まりで触れている場所を求める(
        &self,
        カプセル: &形を掃引するカプセル,
        求解: &カプセルと三角形の接触の求解<'_>,
    ) -> Result<Option<三角形で触れた場所>, 三角形の問い合わせエラー> {
        if let Some(貫いた場所) = self.軸が三角形を貫く場所を求める(カプセル)? {
            return Ok(求解.面へ向かう接触か(&貫いた場所).then_some(貫いた場所));
        }
        Ok(求解.掃引の始まりで触れている最も近い特徴を求める()?.map(|最近接| 最近接.場所()))
    }

    // 掃引の始まりで軸そのものが三角形と交わる場所。接触位置から軸へ向かう変位には、軸の始点が在る側を向く
    // 面の単位法線を置く。軸が面を貫いているとき、この向きが押し戻す向きの代わりになる。
    fn 軸が三角形を貫く場所を求める(
        &self,
        カプセル: &形を掃引するカプセル,
    ) -> Result<Option<三角形で触れた場所>, 三角形の問い合わせエラー> {
        let 軸の線分 = 形を貫く線分::生成する(カプセル.軸の始点(), カプセル.軸の終点());
        match self.線分の問い合わせ().線分が三角形に最初に当たる点を求める(&軸の線分)? {
            線分が三角形に最初に当たる点::三角形に当たらない => Ok(None),
            線分が三角形に最初に当たる点::三角形に当たる(当たり) => Ok(Some(三角形で触れた場所::生成する(
                当たり.交差位置(),
                self.軸の始点が在る側を向く法線の変位(カプセル),
                当たり.当たった特徴(),
            ))),
        }
    }

    // 面の単位法線を、カプセルの軸の始点が在る側へ向けたもの。始点が平面のちょうど上に在るときは、
    // 頂点の並びが決める向きをそのまま返す。
    fn 軸の始点が在る側を向く法線の変位(&self, カプセル: &形を掃引するカプセル) -> 形の局所座標の変位 {
        let 始点の隔たり = self
            .線分の問い合わせ()
            .三角形()
            .頂点の位置(三角形の頂点の番号::第1の頂点)
            .終点までの変位を求める(カプセル.軸の始点())
            .内積(self.面の単位法線の変位());
        if 始点の隔たり < 0.0 {
            self.面の単位法線の変位().実数倍する(-1.0)
        } else {
            self.面の単位法線の変位()
        }
    }
}
