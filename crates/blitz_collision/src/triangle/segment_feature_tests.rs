//! 線分が三角形のどの特徴に当たったかの反証。面の内側・辺のちょうど上・頂点のちょうど上・辺の延長をかすめる
//! 線分と、面積が零の三角形を見る。
//!
//! 辺と頂点の期待値は、交点をそれらの上へ厳密に置いて書く。見本の三角形の辺は座標軸に沿っており、交点の成分が
//! 2進で割り切れる値になるため、辺ごとの符号がちょうど零になる。幅を置かずに零を見る判定がこれで反証できる。

use super::error::三角形の問い合わせエラー;
use super::feature::三角形で当たった特徴;
use super::query_fixture::{
    三角形を作る, 位置の成分, 線分の当たりを取り出す, 見本の三角形への線分の当たりを求める
};
use super::segment_hit::線分が三角形に最初に当たる点;
use super::segment_query::三角形の線分の問い合わせ;
use crate::shape::三角形の頂点の番号;

#[test]
fn 面の内側を貫く線分は面として答える() {
    let 当たり = 線分の当たりを取り出す(見本の三角形への線分の当たりを求める([1.0, 2.0, 1.0], [1.0, -2.0, 1.0]));
    assert_eq!(当たり.当たった特徴(), 三角形で当たった特徴::三角形の面);
}

#[test]
fn 辺のちょうど上を通る線分は辺として答える() {
    let 当たり = 線分の当たりを取り出す(見本の三角形への線分の当たりを求める([2.0, 1.0, 0.0], [2.0, -1.0, 0.0]));
    assert_eq!(位置の成分(当たり.交差位置()), [2.0, 0.0, 0.0]);
    assert_eq!(
        当たり.当たった特徴(),
        三角形で当たった特徴::三角形の辺 {
            始まりの頂点: 三角形の頂点の番号::第1の頂点
        }
    );
}

#[test]
fn 頂点のちょうど上を通る線分は頂点として答える() {
    let 当たり = 線分の当たりを取り出す(見本の三角形への線分の当たりを求める([4.0, 1.0, 0.0], [4.0, -1.0, 0.0]));
    assert_eq!(位置の成分(当たり.交差位置()), [4.0, 0.0, 0.0]);
    assert_eq!(当たり.当たった特徴(), 三角形で当たった特徴::三角形の頂点(三角形の頂点の番号::第2の頂点));
}

#[test]
fn 辺の延長の上をかすめる線分は当たらない() {
    assert_eq!(
        見本の三角形への線分の当たりを求める([5.0, 1.0, 0.0], [5.0, -1.0, 0.0]),
        線分が三角形に最初に当たる点::三角形に当たらない
    );
}

#[test]
fn 面積が零の三角形は線分の問い合わせを組めない() {
    assert_eq!(
        三角形の線分の問い合わせ::三角形から生成する(三角形を作る([[0.0, 0.0, 0.0], [1.0, 2.0, 3.0], [2.0, 4.0, 6.0]])).err(),
        Some(三角形の問い合わせエラー::三角形の面積が零で平面が定まらない)
    );
}
