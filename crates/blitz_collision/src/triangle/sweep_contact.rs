//! 掃引したカプセルが三角形に最初に触れた点と、触れなかったことを表す枝。
//!
//! 接触が持つのは幾何学的な事実だけであり、そこで止まるか滑るか登れるかという意味付けは持たない。
//!
//! 動けた割合と接触位置は同じ1つの時刻から導いている。接触位置は三角形の上の点であり、その時刻のカプセルの
//! 表面もその点を通る。接触の単位法線は接触位置からカプセルの軸へ向かう向きであり、面に触れたときは
//! その三角形の面の単位法線(裏から触れたならその逆向き)と同じ値である。

use blitz_math::{ローカル, 方向};

use crate::shape::形の局所座標の位置;
use crate::solver::掃引で動けた割合;

use super::feature::三角形で当たった特徴;

/// 掃引したカプセルが三角形に最初に触れた点。変位の全体を動いても触れなかった枝と、触れた接触を持つ枝の2つである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum カプセルが三角形に最初に触れる点 {
    /// 変位の全体を動いても三角形に触れなかった。
    三角形に触れない,
    /// 変位の途中で三角形に触れ、その最初の接触を持つ。
    三角形に触れる(掃引したカプセルの三角形への接触),
}

/// 掃引したカプセルが三角形へ触れた1つの事実。動けた割合・接触位置・接触の単位法線・触れた特徴を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 掃引したカプセルの三角形への接触 {
    動けた割合: 掃引で動けた割合,
    接触位置: 形の局所座標の位置,
    接触の単位法線: 方向<ローカル>,
    触れた特徴: 三角形で当たった特徴,
}

impl 掃引したカプセルの三角形への接触 {
    pub(super) fn 生成する(
        動けた割合: 掃引で動けた割合,
        接触位置: 形の局所座標の位置,
        接触の単位法線: 方向<ローカル>,
        触れた特徴: 三角形で当たった特徴,
    ) -> Self {
        Self {
            動けた割合,
            接触位置,
            接触の単位法線,
            触れた特徴,
        }
    }

    /// 掃引の変位のうち、三角形に触れるまでに動けた分の割合。動く前から触れていた場合は0である。
    pub fn 動けた割合(&self) -> 掃引で動けた割合 {
        self.動けた割合
    }

    /// 三角形の上の接触点。その時刻のカプセルの表面もこの点を通る。
    pub fn 接触位置(&self) -> 形の局所座標の位置 {
        self.接触位置
    }

    /// 接触位置からカプセルの軸へ向かう単位方向。軸そのものが三角形を貫いていて向きが定まらない場合は、
    /// 軸の始点が在る側を向く面の単位法線を代わりに返す。
    pub fn 接触の単位法線(&self) -> 方向<ローカル> {
        self.接触の単位法線
    }

    /// 三角形の面・辺・頂点のどれに触れたか。
    pub fn 触れた特徴(&self) -> 三角形で当たった特徴 {
        self.触れた特徴
    }
}
