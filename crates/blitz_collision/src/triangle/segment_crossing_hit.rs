//! 写した三角形から当たりを組む工程。受け取るのは線分と線分の枠へ写した三角形、返すのは線分がその三角形に
//! 当たる点である。工程を別のファイルへ置くのは、名前の付く入力と出力を持ち、呼び出し元が中身を知らずに
//! 呼べる1つの工程だからである。
//!
//! 交差の時刻は、写した3頂点の媒介変数の座標を頂点ごとの重みで混ぜた分子を、辺ごとの面積の総和で割ったもので
//! ある。線分の中に在るかは商を作る前に分子と総和の符号と大きさで決める。商にする丸めが端の受理を左右しない
//! ためである。
//!
//! 交差の位置は重心座標による3頂点の凸結合であり、平面までの隔たりからも交差の時刻からも組み直さない。
//! 三角形ごとの平面で組み直すと、隣り合う2枚が共有辺の同じ1点について別々の点を評価することになる。
//! 第1の頂点から2本の辺の変位をそれぞれの重心座標だけ進む形で書くのは、重心座標が零の頂点の寄与が値を1つも
//! 動かさず、頂点そのものを踏んだ当たりがその頂点の座標をそのまま返すためである。

use crate::shape::{三角形の頂点の番号, 形の局所座標の位置, 形の局所座標の変位, 形を貫く線分};
use crate::solver::線分の媒介変数;

use super::error::三角形の問い合わせエラー;
use super::segment_feature::零になった辺の並びから当たった特徴を組む;
use super::segment_hit::{三角形への最初の当たり, 線分が三角形に最初に当たる点};
use super::segment_query::三角形の線分の問い合わせ;
use super::sheared_triangle::線分の枠へ写した三角形;

impl 三角形の線分の問い合わせ {
    pub(super) fn 写した三角形から当たりを組む(
        &self,
        線分: &形を貫く線分,
        写した三角形: &線分の枠へ写した三角形,
    ) -> Result<線分が三角形に最初に当たる点, 三角形の問い合わせエラー> {
        let 時刻の分子 = 写した三角形.交差の時刻の分子を求める();
        if !時刻の分子が線分の中を指すか(時刻の分子, 写した三角形.面積の総和()) {
            return Ok(線分が三角形に最初に当たる点::三角形に当たらない);
        }
        let 交差時刻 = 線分の媒介変数::端へ寄せて生成する(時刻の分子 / 写した三角形.面積の総和())?;
        let 単位法線 = self.始点の側を向く単位法線を求める(self.線分の始点から平面までの隔たりを求める(線分))?;
        Ok(線分が三角形に最初に当たる点::三角形に当たる(
            三角形への最初の当たり::生成する(
                交差時刻,
                self.重心座標が指す位置を求める(写した三角形)?,
                単位法線,
                零になった辺の並びから当たった特徴を組む(写した三角形.零になった辺の並びを求める()),
            ),
        ))
    }

    // 重心座標が指す三角形の上の点。第1の頂点から、第2と第3の頂点の重心座標の割合だけ2本の辺の変位を進む。
    fn 重心座標が指す位置を求める(
        &self,
        写した三角形: &線分の枠へ写した三角形,
    ) -> Result<形の局所座標の位置, 三角形の問い合わせエラー> {
        let 進む変位 = self
            .頂点へ重心座標だけ進む変位を求める(写した三角形, 三角形の頂点の番号::第2の頂点)
            .加える(self.頂点へ重心座標だけ進む変位を求める(写した三角形, 三角形の頂点の番号::第3の頂点));
        let 第1の頂点 = self.三角形().頂点の位置(三角形の頂点の番号::第1の頂点);
        Ok(第1の頂点.変位だけ進んだ位置を求める(進む変位)?)
    }

    // 第1の頂点から番号の頂点へ張る辺の変位に、その頂点の重心座標を掛けたもの。
    fn 頂点へ重心座標だけ進む変位を求める(
        &self,
        写した三角形: &線分の枠へ写した三角形,
        番号: 三角形の頂点の番号,
    ) -> 形の局所座標の変位 {
        self.三角形()
            .頂点の位置(三角形の頂点の番号::第1の頂点)
            .終点までの変位を求める(self.三角形().頂点の位置(番号))
            .実数倍する(写した三角形.頂点の重心座標を求める(番号))
    }
}

// 交差の時刻の分子が線分の中(媒介変数が0以上1以下)を指すか。時刻は分子を面積の総和で割ったものであるから、
// 総和が正なら分子が0以上総和以下、負なら総和以上0以下であることと同じである。
fn 時刻の分子が線分の中を指すか(時刻の分子: f64, 面積の総和: f64) -> bool {
    if 面積の総和 > 0.0 {
        (0.0..=面積の総和).contains(&時刻の分子)
    } else {
        (面積の総和..=0.0).contains(&時刻の分子)
    }
}
