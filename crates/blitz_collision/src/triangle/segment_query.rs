//! 三角形の線分の問い合わせ: 始点から終点へ引いた線分が三角形に当たる点を求める操作サービス。三角形と、その
//! 面に垂直な変位をコンストラクタで受け取って保持するため、問い合わせの署名に形が現れない。
//!
//! 1回の問い合わせでヒープを確保しない。持つのは平面までの2つの隔たりと、辺ごとの3つの符号だけである。
//!
//! 方式は2段である。まず3頂点が張る平面までの隔たりを線分の両端で測り、符号が変わる時刻を1次式で解く。次に
//! その時刻の点について辺ごとの符号を見て、三角形の内側に在るかとどの特徴に載っているかを決める。三角形は
//! 厚みを持たないため、当たりは高々1つであり「最初の」当たりを選ぶ比較が要らない。

use blitz_math::{ローカル, 方向};

use crate::shape::{三角形の頂点の番号, 局所座標の三角形, 形の局所座標の変位};
use crate::solver::線分の媒介変数;

use super::error::三角形の問い合わせエラー;
use super::segment::三角形を貫く線分;
use super::segment_feature::点が載る特徴を求める;
use super::segment_hit::{三角形への最初の当たり, 線分が三角形に最初に当たる点};

/// 一般の三角形の線分の問い合わせ。三角形を保持し、線分が当たる点を答える操作サービスである。
pub struct 三角形の線分の問い合わせ {
    三角形: 局所座標の三角形,
    面に垂直な変位: 形の局所座標の変位,
}

impl 三角形の線分の問い合わせ {
    /// 三角形を保持する。面積が零の三角形は平面も向きも定まらないため、ここで型付きエラーで拒む。
    pub fn 三角形から生成する(三角形: 局所座標の三角形) -> Result<Self, 三角形の問い合わせエラー> {
        if 三角形.面積が零か() {
            return Err(三角形の問い合わせエラー::三角形の面積が零で平面が定まらない);
        }
        let 面に垂直な変位 = 三角形.面に垂直な変位を求める();
        Ok(Self {
            三角形, 面に垂直な変位
        })
    }

    /// 線分が三角形に当たる点を求める。始点が平面のちょうど上に在って三角形の内側なら、交差時刻0で当たったものとして返す。
    pub fn 線分が三角形に最初に当たる点を求める(
        &self,
        線分: &三角形を貫く線分,
    ) -> Result<線分が三角形に最初に当たる点, 三角形の問い合わせエラー> {
        let 第1の頂点 = self.三角形.頂点の位置(三角形の頂点の番号::第1の頂点);
        let 始点の隔たり = 第1の頂点.終点までの変位を求める(線分.始点()).内積(self.面に垂直な変位);
        let 終点の隔たり = 第1の頂点.終点までの変位を求める(線分.終点()).内積(self.面に垂直な変位);
        let Some(横切る時刻) = 平面を横切る時刻を求める(始点の隔たり, 終点の隔たり) else {
            return Ok(線分が三角形に最初に当たる点::三角形に当たらない);
        };
        self.横切る時刻から当たりを組む(線分, 横切る時刻, 始点の隔たり)
    }

    // 平面を横切る時刻から答えを組む。時刻は隔たりの商であり、丸めで0や1をわずかに外れうるため端へ寄せて受け取る。
    fn 横切る時刻から当たりを組む(
        &self,
        線分: &三角形を貫く線分,
        横切る時刻: f64,
        始点の隔たり: f64,
    ) -> Result<線分が三角形に最初に当たる点, 三角形の問い合わせエラー> {
        let 交差時刻 = 線分の媒介変数::端へ寄せて生成する(横切る時刻)?;
        let 交差位置 = 線分.線分上の点を求める(交差時刻)?;
        let Some(特徴) = 点が載る特徴を求める(self.三角形.辺ごとの符号を求める(交差位置)) else {
            return Ok(線分が三角形に最初に当たる点::三角形に当たらない);
        };
        Ok(線分が三角形に最初に当たる点::三角形に当たる(
            三角形への最初の当たり::生成する(交差時刻, 交差位置, self.始点の側を向く単位法線を求める(始点の隔たり)?, 特徴),
        ))
    }

    // 面の単位法線を線分の始点が在る側へ向けたもの。始点が平面の上に在ってどちら側から来たかが定まらないときは、
    // 頂点の並びが決める向きをそのまま返す。長さが0で向きが定まらない三角形は生成が拒んでいる。
    fn 始点の側を向く単位法線を求める(
        &self, 始点の隔たり: f64
    ) -> Result<方向<ローカル>, 三角形の問い合わせエラー> {
        let 向き = if 始点の隔たり < 0.0 {
            self.面に垂直な変位.実数倍する(-1.0)
        } else {
            self.面に垂直な変位
        };
        match 向き.長さで正した方向へ狭める() {
            Some(結果) => Ok(結果?),
            None => Err(三角形の問い合わせエラー::接触の単位法線が定まらない),
        }
    }
}

// 線分が三角形の平面を横切る時刻。両端が平面の同じ側に在るなら横切らない。両端がどちらも平面の上に在る場合も
// 値なしを返す。線分が平面の中を走っており、交わりが点でなく線分になって、最初に当たる1点も接触面の向きも
// 定まらないためである。その線分が三角形へ入るなら、辺を共有する隣の三角形が同じ平面に無い限りそちらが答える。
fn 平面を横切る時刻を求める(始点の隔たり: f64, 終点の隔たり: f64) -> Option<f64> {
    if 始点の隔たり * 終点の隔たり > 0.0 {
        return None;
    }
    let 隔たりの差 = 始点の隔たり - 終点の隔たり;
    if 隔たりの差 == 0.0 {
        return None;
    }
    Some(始点の隔たり / 隔たりの差)
}
