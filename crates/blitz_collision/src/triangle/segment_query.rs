//! 三角形の線分の問い合わせ: 始点から終点へ引いた線分が三角形に当たる点を求める操作サービス。面の向きを備えた
//! 三角形をコンストラクタで受け取って保持するため、問い合わせの署名に形が現れない。面の向きを添えた入口を
//! 別に持つのは、三角形網が三角形ごとの面の向きを保持しており、候補1枚ごとに外積と平方根を通し直さないためである。
//!
//! 1回の問い合わせでヒープを確保しない。持つのは写した3つの頂点と、辺ごとの3つの符号付き面積だけである。
//!
//! 方式は、線分の向きから決まる座標枠へ三角形を剪断して写し、写した面で線分が三角形の中を通るかを辺ごとの符号付き
//! 面積で見るものである(Woop・Benthin・Wald 2013 の水密な線分と三角形の交差)。写しが三角形でなく線分から決まる
//! ため、隣り合う2枚が共有する辺について2枚が出す量は符号の反転そのものになり、丸めで2枚ともが「外」と答える
//! 取り逃しが構造的に起きない。交差の時刻も交差の位置も写した量の重心座標から導き、三角形ごとの平面で組み直さない。
//! 参照: `crates/blitz_collision/src/triangle/sheared_triangle.rs`
//!
//! 面の向きは交差の判定に使わない。読むのは、返す単位法線を線分の始点が在る側へ向ける1箇所だけである。
//!
//! 解き方は線分と三角形の平面の関わりで3つに分かれる。平面に載る線分は写した三角形がつぶれて写した量が内外を
//! 1つも語らないため、3次元の辺ごとの符号で解く(`crates/blitz_collision/src/triangle/segment_in_plane.rs`)。
//! 平面と平行で離れた線分は平面と1点も交わらない。残る平面を横切る向きの線分だけが写した面の解き方へ進む。
//! この3つ分けを写した面積でなく両端の平面までの隔たりで判ずる理由は
//! `crates/blitz_collision/src/triangle/segment_plane_relation.rs` にある。

use blitz_math::{ローカル, 方向};

use crate::shape::{
    三角形の頂点の番号, 局所座標の三角形, 形の局所座標の位置, 形の局所座標の変位, 形を貫く線分, 面の向きを備えた三角形
};

use super::error::三角形の問い合わせエラー;
use super::segment_hit::線分が三角形に最初に当たる点;
use super::segment_plane_relation::線分と平面の関わり;
use super::segment_shear_frame::線分に合わせた剪断の座標枠;
use super::sheared_triangle::線分の枠へ写した三角形;

/// 一般の三角形の線分の問い合わせ。面の向きを備えた三角形を保持し、線分が当たる点を答える操作サービスである。
pub struct 三角形の線分の問い合わせ {
    三角形: 面の向きを備えた三角形,
}

impl 三角形の線分の問い合わせ {
    /// 三角形から面の向きを求めて保持する。面積が零の三角形は平面も向きも定まらないため、型付きエラーで拒む。
    pub fn 三角形から生成する(三角形: 局所座標の三角形) -> Result<Self, 三角形の問い合わせエラー> {
        let Some(三角形) = 面の向きを備えた三角形::三角形から生成する(三角形) else {
            return Err(三角形の問い合わせエラー::三角形の面積が零で平面が定まらない);
        };
        Ok(Self { 三角形 })
    }

    /// 面の向きを既に備えた三角形を保持する。三角形網が三角形ごとの面の向きを持っており、候補1枚ごとに
    /// 外積と平方根を通し直さないための入口である。向きが定まっていることは受け取る型が保証する。
    pub fn 面の向きを備えた三角形から生成する(三角形: 面の向きを備えた三角形) -> Self {
        Self { 三角形 }
    }

    // 保持している三角形。掃引の問い合わせがこの問い合わせを保持し、同じ三角形を使うために読む。
    pub(super) fn 三角形(&self) -> &面の向きを備えた三角形 {
        &self.三角形
    }

    /// 線分が三角形に当たる点を求める。始点が平面のちょうど上に在って三角形の内側なら、交差時刻0で当たったものとして返す。
    pub fn 線分が三角形に最初に当たる点を求める(
        &self,
        線分: &形を貫く線分,
    ) -> Result<線分が三角形に最初に当たる点, 三角形の問い合わせエラー> {
        let Some(枠) = 線分に合わせた剪断の座標枠::線分から生成する(線分) else {
            return self.始点と終点が同じ線分の当たりを組む(線分);
        };
        match self.線分と平面の関わりを判ずる(線分) {
            線分と平面の関わり::平面に載っている => self.平面の中を走る線分の当たりを組む(線分),
            線分と平面の関わり::平面と平行で離れている => Ok(線分が三角形に最初に当たる点::三角形に当たらない),
            線分と平面の関わり::平面を横切る向きである => self.平面を横切る向きの線分の当たりを組む(線分, &枠),
        }
    }

    // 平面を横切る向きの線分の当たり。線分の枠へ三角形を写し、写した面での辺ごとの符号付き面積で内外を決める。
    fn 平面を横切る向きの線分の当たりを組む(
        &self,
        線分: &形を貫く線分,
        枠: &線分に合わせた剪断の座標枠,
    ) -> Result<線分が三角形に最初に当たる点, 三角形の問い合わせエラー> {
        let 写した三角形 = 線分の枠へ写した三角形::枠で写して組む(枠, &self.三角形);
        if 写した三角形.線分が三角形の外を通るか() {
            return Ok(線分が三角形に最初に当たる点::三角形に当たらない);
        }
        // 面積の総和が零になるのは写した三角形が1本の直線へつぶれた場合である。線分の向きが平面と平行でないことは
        // 関わりの判定で確かめてあるため、数学の上では総和は零にならない。ここへ来るのは平面に対して極めて浅い
        // 向きの線分だけであり、剪断した座標が丸めで揃って3つの面積とも零になった場合である。重心座標も交差の
        // 時刻も総和で割って求めるため、割る前に当たらないとして閉じる。共有辺を挟む隣の枚は同じ写しから同じ零を
        // 得るため、2枚の答えが食い違うことはない。
        if 写した三角形.面積の総和() == 0.0 {
            return Ok(線分が三角形に最初に当たる点::三角形に当たらない);
        }
        self.写した三角形から当たりを組む(線分, &写した三角形)
    }

    // 始点と終点が同じ線分の当たり。向きが定まらず座標枠を組めないため、その1点が三角形の平面に載るかで分かれる。
    // 載るなら平面の中を走る線分と同じ経路が、点が三角形の内側に在るかを辺ごとの符号で決める。
    fn 始点と終点が同じ線分の当たりを組む(
        &self,
        線分: &形を貫く線分,
    ) -> Result<線分が三角形に最初に当たる点, 三角形の問い合わせエラー> {
        if self.点から平面までの隔たりを求める(線分.始点()) != 0.0 {
            return Ok(線分が三角形に最初に当たる点::三角形に当たらない);
        }
        self.平面の中を走る線分の当たりを組む(線分)
    }

    // 点から三角形の平面までの隔たり。面に垂直な変位で測るため長さの単位ではなく、使うのは符号と、2点の値が
    // 一致するかだけである。剪断を1つも通さないため、線分の向きが決める剪断の係数の丸めがこの値に入らない。
    pub(super) fn 点から平面までの隔たりを求める(&self, 点: 形の局所座標の位置) -> f64 {
        self.三角形
            .頂点の位置(三角形の頂点の番号::第1の頂点)
            .終点までの変位を求める(点)
            .内積(self.三角形.面に垂直な変位())
    }

    // 面の単位法線を線分の始点が在る側へ向けたもの。始点が平面の上に在ってどちら側から来たかが定まらないときは、
    // 頂点の並びが決める向きをそのまま返す。長さが0で向きが定まらない三角形は生成が拒んでいる。
    pub(super) fn 始点の側を向く単位法線を求める(
        &self,
        始点から平面までの隔たり: f64,
    ) -> Result<方向<ローカル>, 三角形の問い合わせエラー> {
        if 始点から平面までの隔たり < 0.0 {
            return 変位を単位法線へ狭める(self.三角形.面に垂直な変位().実数倍する(-1.0));
        }
        self.頂点の並びが決める単位法線を求める()
    }

    // 頂点の並びが決める面の向きを長さ1に正したもの。線分がどちら側から来たかが定まらない場合に返す向きである。
    pub(super) fn 頂点の並びが決める単位法線を求める(&self) -> Result<方向<ローカル>, 三角形の問い合わせエラー> {
        変位を単位法線へ狭める(self.三角形.面に垂直な変位())
    }
}

// 面に垂直な変位を長さ1の方向へ狭める。長さが0で向きが定まらない三角形は問い合わせの生成が拒んでいるため、
// ここへ長さ0が来たらそれは破れた不変条件であり、型付きエラーで上へ返す。
fn 変位を単位法線へ狭める(向き: 形の局所座標の変位) -> Result<方向<ローカル>, 三角形の問い合わせエラー> {
    match 向き.長さで正した方向へ狭める() {
        Some(結果) => Ok(結果?),
        None => Err(三角形の問い合わせエラー::接触の単位法線が定まらない),
    }
}
