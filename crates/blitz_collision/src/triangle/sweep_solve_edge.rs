//! 三角形の辺と軸の端の接触、および辺に触れた最近接の組み立て。
//!
//! 半径の球が辺の直線へ達する条件は、中心から直線までの隔たりが半径に等しいことである。その隔たりの二乗は
//! 「辺の始点から中心への変位と辺の変位の外積」の長さの二乗を辺の長さの二乗で割ったものであるから、
//! 分母を払うと時刻の2次方程式になる。直線は辺より長いため、根の時刻で最近接点が辺の内側に収まることを確かめる。
//! 収まらない接触は、辺の端すなわち三角形の頂点の候補が答える。
//!
//! 2つの頂点が重なった三角形では辺の長さが0になり、直線が定まらない。その辺の接触は頂点の候補が答える。

use crate::shape::{三角形の頂点の番号, 形の局所座標の変位};
use crate::solver::掃引の2次方程式;
use crate::solver::軸の端;

use super::error::三角形の問い合わせエラー;
use super::feature::三角形で当たった特徴;
use super::sweep_place::{三角形で触れた場所, 軸と特徴の最近接};
use super::sweep_solver::カプセルと三角形の接触の求解;

impl カプセルと三角形の接触の求解<'_> {
    pub(super) fn 辺と軸の端の方程式を組む(
        &self, 端: 軸の端, 始まりの頂点: 三角形の頂点の番号
    ) -> Option<掃引の2次方程式> {
        let 辺の変位 = self.三角形().辺の変位を求める(始まりの頂点);
        let 辺の長さの二乗 = 辺の変位.長さの二乗();
        if 辺の長さの二乗 <= 0.0 {
            return None;
        }
        Some(掃引の2次方程式::直線と球の隔たりから組む(
            self.頂点から時刻の軸の端への変位(始まりの頂点, 端, 0.0),
            self.掃引の変位(),
            辺の変位,
            辺の長さの二乗,
            self.半径の二乗(),
        ))
    }

    // 時刻での、辺の直線と軸の端の最近接。最近接点が辺の外にあるなら値なしを返す。
    pub(super) fn 辺と軸の端の最近接を求める(
        &self,
        端: 軸の端,
        始まりの頂点: 三角形の頂点の番号,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, 三角形の問い合わせエラー> {
        let 辺の変位 = self.三角形().辺の変位を求める(始まりの頂点);
        let 辺の長さの二乗 = 辺の変位.長さの二乗();
        if 辺の長さの二乗 <= 0.0 {
            return Ok(None);
        }
        let 辺の始点から軸へ = self.頂点から時刻の軸の端への変位(始まりの頂点, 端, 時刻);
        let 辺の比 = 辺の始点から軸へ.内積(辺の変位) / 辺の長さの二乗;
        if !(0.0..=1.0).contains(&辺の比) {
            return Ok(None);
        }
        let 接触点から軸へ = 辺の始点から軸へ.引く(辺の変位.実数倍する(辺の比));
        Ok(Some(self.辺に触れた最近接を組む(始まりの頂点, 辺の比, 接触点から軸へ)?))
    }

    // 辺の上の1点に触れた最近接を組む。接触位置は辺の始点から辺の変位を比の分だけ進めた点である。
    pub(super) fn 辺に触れた最近接を組む(
        &self,
        始まりの頂点: 三角形の頂点の番号,
        辺の比: f64,
        接触点から軸へ: 形の局所座標の変位,
    ) -> Result<軸と特徴の最近接, 三角形の問い合わせエラー> {
        let 接触位置 = self
            .三角形()
            .頂点の位置(始まりの頂点)
            .変位だけ進んだ位置を求める(self.三角形().辺の変位を求める(始まりの頂点).実数倍する(辺の比))?;
        Ok(軸と特徴の最近接::生成する(
            接触点から軸へ.長さの二乗(),
            三角形で触れた場所::生成する(接触位置, 接触点から軸へ, 三角形で当たった特徴::三角形の辺 { 始まりの頂点 }),
        ))
    }
}
