//! 三角形の面と軸の端の接触。触れるのは三角形が乗る平面と、軸の端に置いた半径の球だけである。
//!
//! 球と平面の隔たりは時刻の1次式であるから、隔たりが半径に等しくなる時刻も1次で決まる。それでも2乗した形の
//! 方程式で解くのは、面の表からも裏からも触れうるためである。1次式のまま解くと符号ごとに2本の式になる。
//! 2乗した式の2次の係数は変位の法線成分の2乗であり、法線と垂直に動く掃引では0になって1次式へ退化する。
//!
//! 平面は三角形より広いため、根の時刻での接触点が三角形の内側に無ければその根を捨てる。
//! 捨てた接触は、面ではなく辺か頂点の候補が答える。

use crate::shape::三角形の頂点の番号;
use crate::solver::掃引の2次方程式;
use crate::solver::軸の端;

use super::error::三角形の問い合わせエラー;
use super::feature::三角形で当たった特徴;
use super::sweep_place::{三角形で触れた場所, 軸と特徴の最近接};
use super::sweep_solver::カプセルと三角形の接触の求解;

impl カプセルと三角形の接触の求解<'_> {
    pub(super) fn 面と軸の端の方程式を組む(&self, 端: 軸の端) -> 掃引の2次方程式 {
        let 法線 = self.面の単位法線の変位();
        掃引の2次方程式::平面と球の隔たりから組む(
            self.頂点から時刻の軸の端への変位(三角形の頂点の番号::第1の頂点, 端, 0.0).内積(法線),
            self.掃引の変位().内積(法線),
            self.半径の二乗(),
        )
    }

    // 時刻での、三角形の面と軸の端の最近接。球の中心を平面へ落とした点が三角形の外にあるなら、
    // その点は面での接触ではないため値なしを返す。
    pub(super) fn 面と軸の端の最近接を求める(
        &self,
        端: 軸の端,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, 三角形の問い合わせエラー> {
        let 法線 = self.面の単位法線の変位();
        let 頂点から軸へ = self.頂点から時刻の軸の端への変位(三角形の頂点の番号::第1の頂点, 端, 時刻);
        let 符号付きの隔たり = 頂点から軸へ.内積(法線);
        let 接触位置 = self
            .時刻の軸の端の位置(端, 時刻)?
            .変位だけ進んだ位置を求める(法線.実数倍する(-符号付きの隔たり))?;
        if !self.三角形().面の上の点が内側にあるか(接触位置) {
            return Ok(None);
        }
        Ok(Some(軸と特徴の最近接::生成する(
            符号付きの隔たり * 符号付きの隔たり,
            三角形で触れた場所::生成する(接触位置, 法線.実数倍する(符号付きの隔たり), 三角形で当たった特徴::三角形の面),
        )))
    }
}
