//! 掃引の変位だけである。始まりから触れている候補(`sweep_start_overlap.rs`)と掃引の途中の根(`sweep_solver.rs`)の
//! 両方がこの判定を通す。規則そのものは求解の部品が持つ。
//!
//! 軸そのものが三角形を貫く場所は、接触位置から軸へ向かう変位に軸の始点が在る側を向く面の単位法線を置いているため、
//! 零の変位を別に扱う枝は要らない。
//! 参照: `crates/blitz_collision/src/solver/approach.rs`

use crate::solver::掃引が面へ向かうかの判定;

