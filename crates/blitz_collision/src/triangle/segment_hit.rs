//! 線分が三角形に最初に当たった点と、当たらなかったことを表す枝。
//!
//! 当たりが持つのは幾何学的な事実だけである。壁か床か、そこで止まるか滑るかという意味付けは持たない。
//!
//! 接触面の単位法線を単精度の方向で持つのは、任意姿勢の直方体の当たりと揃えるためである。位置は倍精度のまま
//! 返す。位置は原点から遠いほど単精度の刻みが粗くなり、狭めると当たりの点が形の外へ出うるからである。
//!
//! 法線は線分の始点が在る側を向く。両面から当たるためであり、裏から当たった線分へ表の向きを返すと、押し戻す
//! 側の呼び出しが線分の進む向きへ押すことになる。始点が平面の上に在ってどちら側から来たかが定まらないときは、
//! 頂点の並びが決める向きをそのまま返す。

use blitz_math::{ローカル, 方向};

use crate::shape::形の局所座標の位置;
use crate::solver::線分の媒介変数;

use super::feature::三角形で当たった特徴;

/// 線分が三角形に最初に当たった点。終点まで当たらなかった枝と、当たりを持つ枝の2つである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 線分が三角形に最初に当たる点 {
    /// 終点まで三角形に当たらなかった。
    三角形に当たらない,
    /// 線分の途中で三角形に当たり、その最初の当たりを持つ。
    三角形に当たる(三角形への最初の当たり),
}

/// 線分が三角形に当たった1つの事実。交差時刻・交差位置・接触面の単位法線・当たった特徴を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 三角形への最初の当たり {
    交差時刻: 線分の媒介変数,
    交差位置: 形の局所座標の位置,
    接触面の単位法線: 方向<ローカル>,
    当たった特徴: 三角形で当たった特徴,
}

impl 三角形への最初の当たり {
    pub(super) fn 生成する(
        交差時刻: 線分の媒介変数,
        交差位置: 形の局所座標の位置,
        接触面の単位法線: 方向<ローカル>,
        当たった特徴: 三角形で当たった特徴,
    ) -> Self {
        Self {
            交差時刻,
            交差位置,
            接触面の単位法線,
            当たった特徴,
        }
    }

    /// 線分の始点を0、終点を1として測った、三角形の面へ達した時刻。三角形は厚みを持たないため当たりは高々1つであり、
    /// この時刻が最初の当たりの時刻そのものになる。
    pub fn 交差時刻(&self) -> 線分の媒介変数 {
        self.交差時刻
    }

    /// 線分の上の点として求めた交差の位置。
    pub fn 交差位置(&self) -> 形の局所座標の位置 {
        self.交差位置
    }

    /// 面の単位法線を、線分の始点が在る側へ向けたもの。辺と頂点に当たった場合も同じ面の法線を返す。
    /// 三角形1枚では、辺と頂点の外側がどちらを向くかを決める隣の面が無いためである。
    pub fn 接触面の単位法線(&self) -> 方向<ローカル> {
        self.接触面の単位法線
    }

    /// 三角形の面・辺・頂点のどれに当たったか。
    pub fn 当たった特徴(&self) -> 三角形で当たった特徴 {
        self.当たった特徴
    }
}
