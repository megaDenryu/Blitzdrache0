//! 三角形の平面の中を走る線分の当たりの反証。三角形の外から辺へ入る線分・内側から始まる線分・辺の直線の上を
//! 走る線分・三角形と交わらない線分の4つの状況を見る。
//!
//! 期待値は`query_fixture.rs`の水平な直角三角形で手計算する。頂点は(0,0,0)・(4,0,0)・(0,0,4)であり、面に
//! 垂直な変位は天頂の負の向きの長さ16の変位である。この三角形について、辺ごとの符号は東の座標をx・南の座標をz
//! と書くと、第1の辺(z=0の辺)が64z、第2の辺(斜辺)が64(4-x-z)、第3の辺(x=0の辺)が64xになる。したがって
//! 平面の中の線分の内外は、この3つの1次式の符号だけで決まる。
//!
//! 返す単位法線はどの状況でも頂点の並びが決める向きである。平面の中では線分の始点がどちら側に在るかが定まらず、
//! 両面当たりの規約が適用できないためである。

use crate::shape::三角形の頂点の番号;

use super::feature::三角形で当たった特徴;
use super::query_fixture::{
    位置の成分, 方向の成分, 線分の当たりを取り出す, 見本の三角形への線分の当たりを求める
};
use super::segment_hit::線分が三角形に最初に当たる点;

#[test]
fn 平面の中を外から入る線分は辺を踏む媒介変数で当たる() {
    let 当たり = 線分の当たりを取り出す(見本の三角形への線分の当たりを求める([-1.0, 0.0, 1.0], [3.0, 0.0, 1.0]));
    assert_eq!(当たり.交差時刻().値(), 0.25);
    assert_eq!(位置の成分(当たり.交差位置()), [0.0, 0.0, 1.0]);
    assert_eq!(方向の成分(当たり.接触面の単位法線()), [0.0, -1.0, 0.0]);
    assert_eq!(
        当たり.当たった特徴(),
        三角形で当たった特徴::三角形の辺 {
            始まりの頂点: 三角形の頂点の番号::第3の頂点
        }
    );
}

#[test]
fn 平面の中の三角形の内側から始まる線分は媒介変数0で面に当たる() {
    let 当たり = 線分の当たりを取り出す(見本の三角形への線分の当たりを求める([1.0, 0.0, 1.0], [5.0, 0.0, 1.0]));
    assert_eq!(当たり.交差時刻().値(), 0.0);
    assert_eq!(位置の成分(当たり.交差位置()), [1.0, 0.0, 1.0]);
    assert_eq!(当たり.当たった特徴(), 三角形で当たった特徴::三角形の面);
}

#[test]
fn 辺の直線の上を走る線分は頂点を踏む媒介変数で当たる() {
    let 当たり = 線分の当たりを取り出す(見本の三角形への線分の当たりを求める([-1.0, 0.0, 0.0], [3.0, 0.0, 0.0]));
    assert_eq!(当たり.交差時刻().値(), 0.25);
    assert_eq!(位置の成分(当たり.交差位置()), [0.0, 0.0, 0.0]);
    assert_eq!(当たり.当たった特徴(), 三角形で当たった特徴::三角形の頂点(三角形の頂点の番号::第1の頂点));
}

#[test]
fn 平面の中でも三角形を外れる線分は当たらない() {
    assert_eq!(
        見本の三角形への線分の当たりを求める([5.0, 0.0, 5.0], [6.0, 0.0, 6.0]),
        線分が三角形に最初に当たる点::三角形に当たらない
    );
    assert_eq!(
        見本の三角形への線分の当たりを求める([-1.0, 0.0, -1.0], [-1.0, 0.0, 5.0]),
        線分が三角形に最初に当たる点::三角形に当たらない
    );
}
