//! カプセルの掃引の反証が共有する入口。見本の三角形へ掃引を投げる道具と、答えから接触を取り出す読み取りを持つ。
//!
//! 三角形と線分を組む道具(`query_fixture.rs`)と別に置くのは、掃引の入口が半径と変位という2つの材料を余計に
//! 取るためである。線分の反証にその2つは要らない。
//!
//! 見本の三角形は線分の反証と同じ水平な直角三角形である。期待値の手計算が、面の単位法線が天頂の負の向きで
//! あることを前提に書かれている。

use crate::shape::{形の局所座標の変位, 形を掃引するカプセル};

use super::query_fixture::{局所の点, 水平な直角三角形};
use super::sweep_contact::{カプセルが三角形に最初に触れる点, 掃引したカプセルの三角形への接触};
use super::sweep_query::三角形のカプセルの掃引の問い合わせ;

// 位置と法線の比較に許す幅。根が2進で割り切れない組でも、時刻から位置を組み直す誤差はこの幅に収まる。
pub(super) const 掃引の反証が許す幅: f64 = 1.0e-12;

pub(super) fn 見本の三角形への掃引の接触を求める(
    軸の始点: [f64; 3],
    軸の終点: [f64; 3],
    半径のメートル: f64,
    掃引の変位: [f64; 3],
) -> カプセルが三角形に最初に触れる点 {
    let 問い合わせ = match 三角形のカプセルの掃引の問い合わせ::三角形から生成する(水平な直角三角形()) {
        Ok(問い合わせ) => 問い合わせ,
        Err(誤り) => panic!("試験用の三角形の掃引の問い合わせを作れなかった: {誤り}"),
    };
    match 問い合わせ.カプセルが三角形に最初に触れる点を求める(&カプセルを作る(軸の始点, 軸の終点, 半径のメートル, 掃引の変位))
    {
        Ok(答え) => 答え,
        Err(誤り) => panic!("掃引の問い合わせが失敗した: {誤り}"),
    }
}

pub(super) fn 掃引の接触を取り出す(
    答え: カプセルが三角形に最初に触れる点
) -> 掃引したカプセルの三角形への接触 {
    match 答え {
        カプセルが三角形に最初に触れる点::三角形に触れる(接触) => 接触,
        カプセルが三角形に最初に触れる点::三角形に触れない => panic!("触れるはずのカプセルが触れなかった"),
    }
}

fn カプセルを作る(
    軸の始点: [f64; 3], 軸の終点: [f64; 3], 半径のメートル: f64, 掃引の変位: [f64; 3]
) -> 形を掃引するカプセル {
    match 形を掃引するカプセル::生成する(局所の点(軸の始点), 局所の点(軸の終点), 半径のメートル, 局所の変位(掃引の変位))
    {
        Ok(カプセル) => カプセル,
        Err(誤り) => panic!("試験用のカプセルを作れなかった: {誤り}"),
    }
}

fn 局所の変位(成分: [f64; 3]) -> 形の局所座標の変位 {
    match 形の局所座標の変位::生成する(成分[0], 成分[1], 成分[2]) {
        Ok(変位) => 変位,
        Err(誤り) => panic!("試験用の局所の変位を作れなかった: {誤り}"),
    }
}
