//! 掃引の求解が特徴ごとに持ち回る3つの値。触れた場所そのものと、それに隔たりを添えたもの、時刻を添えたものである。
//!
//! 触れた場所は、三角形の上のどの点に、どの向きから、どの特徴として触れたかを持つ。時刻も隔たりも持たない。
//! 同じ場所が「掃引の途中で初めて触れる場所」としても「掃引の始まりで最も近い場所」としても現れ、
//! 時刻と隔たりはその2つの用途がそれぞれ持つためである。
//!
//! 接触の向きを単位方向へ正さずに倍精度の変位のまま持つのは、20通りの候補それぞれで平方根と割り算を通すのを
//! 避けるためである。正すのは最小の候補が決まった1件についてだけでよい。長さが0でこの向きが定まらない場合は、
//! 答えを組む側が面の単位法線を代わりに使う。

use crate::shape::{形の局所座標の位置, 形の局所座標の変位};
use crate::solver::掃引で動けた割合;

use super::feature::三角形で当たった特徴;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 三角形で触れた場所 {
    接触位置: 形の局所座標の位置,
    接触位置から軸への変位: 形の局所座標の変位,
    触れた特徴: 三角形で当たった特徴,
}

impl 三角形で触れた場所 {
    pub(super) fn 生成する(
        接触位置: 形の局所座標の位置, 接触位置から軸への変位: 形の局所座標の変位, 触れた特徴: 三角形で当たった特徴
    ) -> Self {
        Self {
            接触位置,
            接触位置から軸への変位,
            触れた特徴,
        }
    }

    pub(super) fn 接触位置(&self) -> 形の局所座標の位置 {
        self.接触位置
    }

    pub(super) fn 接触位置から軸への変位(&self) -> 形の局所座標の変位 {
        self.接触位置から軸への変位
    }

    pub(super) fn 触れた特徴(&self) -> 三角形で当たった特徴 {
        self.触れた特徴
    }
}

// ある時刻での、カプセルの軸と三角形の1つの特徴の最近接。隔たりを二乗のまま持つのは、半径との比較を
// 平方根を通さずに行えるためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 軸と特徴の最近接 {
    隔たりの二乗: f64,
    場所: 三角形で触れた場所,
}

impl 軸と特徴の最近接 {
    pub(super) fn 生成する(隔たりの二乗: f64, 場所: 三角形で触れた場所) -> Self {
        Self { 隔たりの二乗, 場所 }
    }

    pub(super) fn 隔たりの二乗(&self) -> f64 {
        self.隔たりの二乗
    }

    pub(super) fn 場所(&self) -> 三角形で触れた場所 {
        self.場所
    }
}

// 掃引の途中で初めて特徴に触れる候補。触れる時刻は掃引で動けた割合そのものであるから、その型で持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 触れ始める候補 {
    動けた割合: 掃引で動けた割合,
    場所: 三角形で触れた場所,
}

impl 触れ始める候補 {
    pub(super) fn 生成する(動けた割合: 掃引で動けた割合, 場所: 三角形で触れた場所) -> Self {
        Self { 動けた割合, 場所 }
    }

    pub(super) fn 動けた割合(&self) -> 掃引で動けた割合 {
        self.動けた割合
    }

    pub(super) fn 場所(&self) -> 三角形で触れた場所 {
        self.場所
    }
}
