//! 線分が三角形の平面を横切る時刻と、当たりが返す単位法線の向きの反証。表からの当たり・裏からの当たり・
//! 平面の上から始まる線分・終点ちょうどで触れる線分・平面から離れた平行な線分・面の手前で終わる線分・
//! 平面の同じ側に在る極めて小さい隔たりの線分を見る。
//!
//! 平面の中を走る線分は`segment_in_plane_tests.rs`が別に見る。こちらの反証は平面を横切る側だけを見る。
//!
//! 期待値は見本の水平な直角三角形で手計算する。この三角形の面に垂直な変位は天頂の負の向きの長さ16の変位で
//! あるから、天頂の高さhの点の平面までの隔たりはマイナス16hであり、横切る時刻は両端の高さの比だけで決まる。
//!
//! どの特徴に当たったかは`segment_feature_tests.rs`が別に見る。時刻と向きの反証に特徴の期待値を混ぜると、
//! 片方が壊れたときにどちらの工程が壊れたのかが読み取れなくなる。

use super::query_fixture::{
    位置の成分, 方向の成分, 線分の当たりを取り出す, 見本の三角形への線分の当たりを求める
};
use super::segment_hit::線分が三角形に最初に当たる点;

#[test]
fn 面を貫く線分は高さの比の時刻で当たり法線は始点の側を向く() {
    let 当たり = 線分の当たりを取り出す(見本の三角形への線分の当たりを求める([1.0, 2.0, 1.0], [1.0, -2.0, 1.0]));
    assert_eq!(当たり.交差時刻().値(), 0.5);
    assert_eq!(位置の成分(当たり.交差位置()), [1.0, 0.0, 1.0]);
    assert_eq!(方向の成分(当たり.接触面の単位法線()), [0.0, 1.0, 0.0]);
}

#[test]
fn 裏から貫く線分も当たり法線は逆を向く() {
    let 当たり = 線分の当たりを取り出す(見本の三角形への線分の当たりを求める([1.0, -3.0, 1.0], [1.0, 1.0, 1.0]));
    assert_eq!(当たり.交差時刻().値(), 0.75);
    assert_eq!(位置の成分(当たり.交差位置()), [1.0, 0.0, 1.0]);
    assert_eq!(方向の成分(当たり.接触面の単位法線()), [0.0, -1.0, 0.0]);
}

#[test]
fn 平面の上から始まる線分は時刻0で当たり法線は頂点の並びの向きになる() {
    let 当たり = 線分の当たりを取り出す(見本の三角形への線分の当たりを求める([1.0, 0.0, 1.0], [1.0, -2.0, 1.0]));
    assert_eq!(当たり.交差時刻().値(), 0.0);
    assert_eq!(位置の成分(当たり.交差位置()), [1.0, 0.0, 1.0]);
    assert_eq!(方向の成分(当たり.接触面の単位法線()), [0.0, -1.0, 0.0]);
}

#[test]
fn 終点ちょうどで面に触れる線分は時刻1で当たる() {
    let 当たり = 線分の当たりを取り出す(見本の三角形への線分の当たりを求める([1.0, 2.0, 1.0], [1.0, 0.0, 1.0]));
    assert_eq!(当たり.交差時刻().値(), 1.0);
    assert_eq!(位置の成分(当たり.交差位置()), [1.0, 0.0, 1.0]);
}

#[test]
fn 平面から離れた平行な線分は当たらない() {
    assert_eq!(
        見本の三角形への線分の当たりを求める([1.0, 1.0, 1.0], [2.0, 1.0, 1.0]),
        線分が三角形に最初に当たる点::三角形に当たらない
    );
}

#[test]
fn 平面の同じ側の極めて小さい隔たりでも当たらない() {
    assert_eq!(
        見本の三角形への線分の当たりを求める([1.0, 1.0e-200, 1.0], [1.0, 2.0e-200, 1.0]),
        線分が三角形に最初に当たる点::三角形に当たらない
    );
    assert_eq!(
        見本の三角形への線分の当たりを求める([1.0, -1.0e-200, 1.0], [1.0, -2.0e-200, 1.0]),
        線分が三角形に最初に当たる点::三角形に当たらない
    );
}

#[test]
fn 面の手前で終わる線分は当たらない() {
    assert_eq!(
        見本の三角形への線分の当たりを求める([1.0, 2.0, 1.0], [1.0, 1.0, 1.0]),
        線分が三角形に最初に当たる点::三角形に当たらない
    );
}
