//! 三角形の平面の中を走る線分の当たり。受け取るのは平面の中を走る線分、返すのはその線分が三角形の内側へ
//! 最初に入る点である。辺ごとの符号の両端の値を持つ型と、その型を使って当たりを組む工程を持つ。
//!
//! 平面の中の線分を一律に当たらないとしないのは、平面の中でも三角形の外から辺へ入る線分には最初の交点が
//! 1点に定まるためである。平らな床を三角形網で作ると、床と同じ高さを滑る線分がすべて素通りする穴になる。
//!
//! 辺ごとの符号は点について1次であるから、線分の上では媒介変数について1次である。したがって両端の符号だけで
//! 線分の全体が決まり、途中の点を組み直さずに区間を切り詰められる。3辺それぞれの「符号が0以上」という条件を
//! 媒介変数の区間へ直し、3つを重ねた区間の入り口が最初に内側へ入る媒介変数である。
//!
//! 主要軸へ射影して2次元で解く形にしないのは、三角形の内外を決める符号が`crate::shape`の
//! `辺ごとの符号を求める`に既に在り、射影で別の式を立てるとその2つが丸めのぶんだけ食い違うためである。
//! 食い違えば、平面を横切る線分と平面の中を走る線分が三角形の縁で別々の答えを返す。射影が避けようとする
//! 退化(面積が零の三角形)は、問い合わせの生成が既に型付きエラーで拒んでいる。
//!
//! 返す単位法線は頂点の並びが決める向きそのものである。線分が平面の中に在るため始点がどちら側に在るかが
//! 定まらず、両面当たりの規約(法線を始点の側へ向ける)が適用できないためである。始点が平面のちょうど上に
//! 在る線分に対して`segment_query.rs`が返す向きと同じ規約であり、2つの入口で向きが割れない。

use crate::shape::局所座標の三角形;
use crate::solver::線分の媒介変数;

use super::error::三角形の問い合わせエラー;
use super::segment::三角形を貫く線分;
use super::segment_feature::零になった辺の並びから当たった特徴を組む;
use super::segment_hit::{三角形への最初の当たり, 線分が三角形に最初に当たる点};
use super::segment_query::三角形の線分の問い合わせ;

impl 三角形の線分の問い合わせ {
    // 平面の中を走る線分の当たり。三角形の内側へ入る最初の媒介変数を辺ごとの符号の区間から求め、
    // その媒介変数で零になる辺の並びが当たった特徴を決める。
    pub(super) fn 平面の中を走る線分の当たりを組む(
        &self,
        線分: &三角形を貫く線分,
    ) -> Result<線分が三角形に最初に当たる点, 三角形の問い合わせエラー> {
        let 符号 = 平面の中を走る線分の辺ごとの符号::線分の両端から求める(self.三角形(), 線分);
        let Some(入る媒介変数) = 符号.三角形の内側へ最初に入る媒介変数を求める() else {
            return Ok(線分が三角形に最初に当たる点::三角形に当たらない);
        };
        let 交差時刻 = 線分の媒介変数::端へ寄せて生成する(入る媒介変数)?;
        Ok(線分が三角形に最初に当たる点::三角形に当たる(
            三角形への最初の当たり::生成する(
                交差時刻,
                線分.線分上の点を求める(交差時刻)?,
                self.頂点の並びが決める単位法線を求める()?,
                零になった辺の並びから当たった特徴を組む(符号.媒介変数で零になる辺の並びを求める(入る媒介変数)),
            ),
        ))
    }
}

// 平面の中を走る線分の、両端それぞれで求めた3辺の符号。辺の符号が媒介変数について1次であることを使い、
// 内側に居る区間の切り詰めと、ある媒介変数で符号が零になる辺の読み取りをこの2組の値だけで行う。
struct 平面の中を走る線分の辺ごとの符号 {
    始点の符号: [f64; 3],
    終点の符号: [f64; 3],
}

impl 平面の中を走る線分の辺ごとの符号 {
    fn 線分の両端から求める(三角形: &局所座標の三角形, 線分: &三角形を貫く線分) -> Self {
        Self {
            始点の符号: 三角形.辺ごとの符号を求める(線分.始点()),
            終点の符号: 三角形.辺ごとの符号を求める(線分.終点()),
        }
    }

    // 三角形の内側へ最初に入る媒介変数。線分が内側を1点も通らないなら値なしを返す。3辺それぞれについて
    // 符号が0以上になる媒介変数の区間を作り、入りの最も遅いものと出の最も早いものを取る。
    fn 三角形の内側へ最初に入る媒介変数を求める(&self) -> Option<f64> {
        let mut 区間の入り = 0.0f64;
        let mut 区間の出 = 1.0f64;
        for 辺 in 0usize..3 {
            let (始点の符号, 終点の符号) = (self.始点の符号[辺], self.終点の符号[辺]);
            let 符号の差 = 始点の符号 - 終点の符号;
            if 符号の差 == 0.0 {
                if 始点の符号 < 0.0 {
                    return None;
                }
                continue;
            }
            let 符号が零になる媒介変数 = 始点の符号 / 符号の差;
            if 符号の差 < 0.0 {
                区間の入り = 区間の入り.max(符号が零になる媒介変数);
            } else {
                区間の出 = 区間の出.min(符号が零になる媒介変数);
            }
        }
        (区間の入り <= 区間の出).then_some(区間の入り)
    }

    // 指定した媒介変数の点で符号が零になる辺の並び。符号は媒介変数について1次であるから、両端がどちらも零の辺
    // (線分がその辺の直線の上を走る場合)と、符号が零になる媒介変数がちょうど一致する辺がこれに当たる。
    fn 媒介変数で零になる辺の並びを求める(&self, 媒介変数: f64) -> [bool; 3] {
        [0usize, 1, 2].map(|辺| {
            let (始点の符号, 終点の符号) = (self.始点の符号[辺], self.終点の符号[辺]);
            if 始点の符号 == 0.0 && 終点の符号 == 0.0 {
                return true;
            }
            始点の符号 != 終点の符号 && 媒介変数 == 始点の符号 / (始点の符号 - 終点の符号)
        })
    }
}
