//! 平面が座標軸を向いていない三角形への線分の反証。平面の中を走る線分と、平面から離れて平行に走る線分を見る。
//!
//! 見本の水平な直角三角形と別に置くのは、あちらの平面が座標軸に垂直であり、線分の向きから決まる剪断の係数が
//! 2進で厳密に表せる値になりやすいためである。平面に載っているかを剪断で写した辺の面積で決めると、係数が
//! 3分の2のように2進で表せない向きでは、平面に載る線分でも面積が零へ揃わず正負が混じり、外を通る判定が
//! 平面の中の経路より先に線分を落とす。この取り逃しは平面が傾いた三角形でしか現れない。
//!
//! 三角形は(0,0,0)・(4,-4,0)・(4,0,-4)であり、面に垂直な変位は(16,16,16)、平面はx+y+z=0になる。したがって
//! 点の平面までの隔たりは3成分の和の16倍であり、整数の座標で厳密に読める。

use crate::shape::{三角形の頂点の番号, 局所座標の三角形};

use super::feature::三角形で当たった特徴;
use super::query_fixture::{三角形への線分の当たりを求める, 三角形を作る, 位置の成分, 線分の当たりを取り出す};
use super::segment_hit::線分が三角形に最初に当たる点;

fn 平面が座標軸を向いていない三角形() -> 局所座標の三角形 {
    三角形を作る([[0.0, 0.0, 0.0], [4.0, -4.0, 0.0], [4.0, 0.0, -4.0]])
}

// 向き(3,-2,-1)の剪断の係数はマイナス3分の2とマイナス3分の1であり、どちらも2進で表せない。
#[test]
fn 剪断の係数が2進で表せない向きでも平面の中の線分は辺の上で当たる() {
    let 当たり = 線分の当たりを取り出す(三角形への線分の当たりを求める(
        平面が座標軸を向いていない三角形(),
        [0.0, 1.0, -1.0],
        [3.0, -1.0, -2.0],
    ));
    assert_eq!(当たり.交差時刻().値(), 0.5);
    assert_eq!(位置の成分(当たり.交差位置()), [1.5, 0.0, -1.5]);
    assert_eq!(
        当たり.当たった特徴(),
        三角形で当たった特徴::三角形の辺 {
            始まりの頂点: 三角形の頂点の番号::第3の頂点
        }
    );
}

// 平面の中の線分を面に垂直な向きへ(1,1,1)だけずらした線分であり、三角形の真上を平行に走る。
#[test]
fn 傾いた平面から離れて平行に走る線分は三角形の真上でも当たらない() {
    assert_eq!(
        三角形への線分の当たりを求める(平面が座標軸を向いていない三角形(), [3.0, 0.0, 0.0], [4.0, 0.0, -1.0]),
        線分が三角形に最初に当たる点::三角形に当たらない
    );
}
