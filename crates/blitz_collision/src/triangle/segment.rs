//! 三角形を貫く線分: 三角形に当たるかを問い合わせる、始点と終点で決まる線分である。
//! 半直線でも直線でもなく線分であるのは、利用者(視点と注視点の間の遮蔽、次の刻みまでの移動)が
//! どちらの端も持っているためである。
//!
//! 端点が有限でありその絶対値が上限に収まることは`形の局所座標の位置`の生成が保証するため、この型は検査を持たない。
//!
//! 任意姿勢の直方体への問い合わせも同じ座標系の同じ形の線分を入力に取る。1つの型に畳まなかったのは、畳むと
//! 世界側(`crates/blitz_engine/src/lib.rs`)の呼び出しを同時に直すことになり、この段の作業が衝突数学層の外へ
//! 出るためである。畳む先は形に依らない入力の型であり、世界側の配線を作る段でまとめて行う。

use crate::shape::{形の局所座標の位置, 形の局所座標の変位};
use crate::solver::線分の媒介変数;

use super::error::三角形の問い合わせエラー;

/// 三角形に当たるかを問い合わせる、始点と終点で決まる線分。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 三角形を貫く線分 {
    始点: 形の局所座標の位置,
    終点: 形の局所座標の位置,
}

impl 三角形を貫く線分 {
    /// 始点と終点から作る。端点の有限性と成分の絶対値の上限は位置の型が守るため、この生成に検査は無い。
    pub fn 生成する(始点: 形の局所座標の位置, 終点: 形の局所座標の位置) -> Self {
        Self { 始点, 終点 }
    }

    /// 線分の媒介変数が0の端。
    pub fn 始点(&self) -> 形の局所座標の位置 {
        self.始点
    }

    /// 線分の媒介変数が1の端。
    pub fn 終点(&self) -> 形の局所座標の位置 {
        self.終点
    }

    /// 始点から終点へ向かう変位。媒介変数が1増えるあいだに進む量である。
    pub fn 始点から終点への変位を求める(&self) -> 形の局所座標の変位 {
        self.始点.終点までの変位を求める(self.終点)
    }

    /// 媒介変数で指し示す線分上の点。始点へ変位の実数倍を足して求めるため、媒介変数が0の端は始点そのものになる。
    /// 端点が有限でも成分の差が浮動小数点の表せる範囲を越えうるため、有限性の検査を通し直す。
    pub fn 線分上の点を求める(
        &self, 媒介変数: 線分の媒介変数
    ) -> Result<形の局所座標の位置, 三角形の問い合わせエラー> {
        Ok(self
            .始点
            .変位だけ進んだ位置を求める(self.始点から終点への変位を求める().実数倍する(媒介変数.値()))?)
    }
}
