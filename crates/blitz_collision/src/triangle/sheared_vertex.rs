//! 線分の枠へ写した頂点: 三角形の頂点を、線分に合わせた剪断の座標枠で写した座標である。3つの成分は、線分を
//! 見下ろす面の横の座標と縦の座標、および線分の媒介変数で測った奥行きの座標である。
//!
//! この写しで線分そのものは横も縦も零の直線になり、媒介変数の座標が0の点から1の点まで進む。したがって
//! 「線分が三角形を貫くか」は、写した面で原点が三角形の中に在るかという2次元の問いへ変わり、「いつ貫くか」は
//! 写した3頂点の媒介変数の座標を重心座標で混ぜる問いへ変わる。
//!
//! 3つの実数を裸で持ち回さないのは、横と縦と媒介変数が別の量であり、並べただけでは取り違えても型が通るためである。

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 線分の枠へ写した頂点 {
    横の座標: f64,
    縦の座標: f64,
    媒介変数の座標: f64,
}

impl 線分の枠へ写した頂点 {
    pub(super) fn 三つの座標から組む(横の座標: f64, 縦の座標: f64, 媒介変数の座標: f64) -> Self {
        Self {
            横の座標,
            縦の座標,
            媒介変数の座標,
        }
    }

    pub(super) fn 横の座標(self) -> f64 {
        self.横の座標
    }

    pub(super) fn 縦の座標(self) -> f64 {
        self.縦の座標
    }

    pub(super) fn 媒介変数の座標(self) -> f64 {
        self.媒介変数の座標
    }
}
