//! 一般の三角形への詳細判定で破れる条件。
//!
//! 形そのものの破れはここに入らない。3つの頂点で表す三角形は、頂点の位置が作れる限り必ず作れるためである。
//! 面積が零の三角形だけは値として作れて問い合わせが組めないため、その破れをここが持つ。拒む地点を問い合わせの
//! 生成に置くのは、面の向きが要るのが判定の側だからである。

use blitz_math::方向エラー;
use thiserror::Error;

use crate::shape::形の局所座標の生成エラー;
use crate::solver::無次元の媒介変数の生成エラー;

/// 一般の三角形への詳細判定で破れる条件。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 三角形の問い合わせエラー {
    /// 三角形の面積が零であり、面が乗る平面とその向きが定まらなかった。
    #[error("三角形の面積が零で平面が定まらない")]
    三角形の面積が零で平面が定まらない,
    /// 問い合わせの点や、求解が導いた接触の点を局所座標の位置として作れなかった。
    #[error("三角形への問い合わせの点を作れない: {0}")]
    問い合わせの点を作れない(#[from] 形の局所座標の生成エラー),
    /// 線分の媒介変数か掃引で動けた割合が、0以上1以下の有限値でなかった。
    #[error("三角形への問い合わせの媒介変数を作れない: {0}")]
    問い合わせの媒介変数を作れない(#[from] 無次元の媒介変数の生成エラー),
    /// 求めた接触の向きを単位方向へ狭められなかった。
    #[error("三角形への接触の単位法線を作れない: {0}")]
    接触の単位法線を作れない(#[from] 方向エラー),
    /// 接触の向きの長さが0であり、単位方向として定まらなかった。
    #[error("三角形への接触の単位法線が長さ0で定まらない")]
    接触の単位法線が定まらない,
}
