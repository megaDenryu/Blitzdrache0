//! 掃引の求解が特徴ごとに持ち回る2つの値。触れた場所そのものと、それに時刻または隔たりを添えたものである。
//!
//! 触れた場所は、静止したカプセルの軸の上のどの点に、どの向きから、どの特徴として触れたかを持つ。時刻も隔たりも
//! 持たない。同じ場所が「掃引の途中で初めて触れる場所」としても「掃引の始まりで最も近い場所」としても現れ、
//! 時刻と隔たりはその2つの用途がそれぞれ持つためである。
//!
//! 持つのが表面の接触点ではなく軸の上の最近接点であるのは、表面の点を作るのに向きを長さ1へ正す割り算と平方根が
//! 要るためである。9通りの候補それぞれでそれを通すのを避け、正すのは最小の候補が決まった1件についてだけにする。
//! 表面の接触点は、答えを組む側が軸の上の最近接点から半径だけその向きへ進めて作る。
//!
//! 長さが0でこの向きが定まらない場合は、答えを組む側が型付きエラーで返す。カプセルの軸の上の点は直方体の面の
//! ような外向きを持たず、代わりに使える向きがこの層に無いためである。

use crate::shape::{形の局所座標の位置, 形の局所座標の変位};
use crate::solver::掃引で動けた割合;

use super::feature::静止したカプセルで触れた特徴;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 静止したカプセルで触れた場所 {
    軸の上の最近接点: 形の局所座標の位置,
    最近接点から掃引する軸への変位: 形の局所座標の変位,
    触れた特徴: 静止したカプセルで触れた特徴,
}

impl 静止したカプセルで触れた場所 {
    pub(super) fn 生成する(
        軸の上の最近接点: 形の局所座標の位置,
        最近接点から掃引する軸への変位: 形の局所座標の変位,
        触れた特徴: 静止したカプセルで触れた特徴,
    ) -> Self {
        Self {
            軸の上の最近接点,
            最近接点から掃引する軸への変位,
            触れた特徴,
        }
    }

    pub(super) fn 軸の上の最近接点(&self) -> 形の局所座標の位置 {
        self.軸の上の最近接点
    }

    pub(super) fn 最近接点から掃引する軸への変位(&self) -> 形の局所座標の変位 {
        self.最近接点から掃引する軸への変位
    }

    pub(super) fn 触れた特徴(&self) -> 静止したカプセルで触れた特徴 {
        self.触れた特徴
    }
}

// ある時刻での、掃引する軸と静止したカプセルの1つの特徴の最近接。隔たりを二乗のまま持つのは、半径の和との
// 比較を平方根を通さずに行えるためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 軸と特徴の最近接 {
    隔たりの二乗: f64,
    場所: 静止したカプセルで触れた場所,
}

impl 軸と特徴の最近接 {
    pub(super) fn 生成する(隔たりの二乗: f64, 場所: 静止したカプセルで触れた場所) -> Self {
        Self { 隔たりの二乗, 場所 }
    }

    pub(super) fn 隔たりの二乗(&self) -> f64 {
        self.隔たりの二乗
    }

    pub(super) fn 場所(&self) -> 静止したカプセルで触れた場所 {
        self.場所
    }
}

// 掃引の途中で初めて特徴に触れる候補。触れる時刻は掃引で動けた割合そのものであるから、その型で持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 触れ始める候補 {
    動けた割合: 掃引で動けた割合,
    場所: 静止したカプセルで触れた場所,
}

impl 触れ始める候補 {
    pub(super) fn 生成する(動けた割合: 掃引で動けた割合, 場所: 静止したカプセルで触れた場所) -> Self {
        Self { 動けた割合, 場所 }
    }

    pub(super) fn 動けた割合(&self) -> 掃引で動けた割合 {
        self.動けた割合
    }

    pub(super) fn 場所(&self) -> 静止したカプセルで触れた場所 {
        self.場所
    }
}
