//! 静止したカプセルへのカプセルの掃引の問い合わせ: カプセルを変位の分だけ動かそうとしたとき、静止したもう1つの
//! カプセルに触れるまでにどこまで動けるかを求める操作サービス。静止したカプセルをコンストラクタで受け取って
//! 保持するため、問い合わせの署名に相手の形が現れない。
//!
//! 1回の問い合わせでヒープを確保しない。持つのは特徴ごとの最小の候補1つだけである。
//!
//! 接触の向きを長さ1に正すのはここ1箇所である。9通りの候補それぞれで平方根と割り算を通すのを避けるため、
//! 求解は軸の上の最近接点から掃引する軸へ向かう倍精度の変位のまま持ち回り、最小の候補が決まってから正す。
//! 正した向きは2つの答えに使う。倍精度のまま半径を掛けて表面の接触位置を作る側と、単精度へ狭めて接触の
//! 単位法線を返す側である。

use crate::shape::{カプセル, 形を掃引するカプセル};
use crate::solver::掃引で動けた割合;

use super::error::カプセルの問い合わせエラー;
use super::sweep_contact::{
    カプセルが静止したカプセルに最初に触れる点, 掃引したカプセルの静止したカプセルへの接触
};
use super::sweep_place::静止したカプセルで触れた場所;
use super::sweep_solver::カプセルどうしの接触の求解;

/// 静止したカプセルへのカプセルの掃引の問い合わせ。静止した相手を保持し、掃引の接触を答える操作サービスである。
pub struct 静止したカプセルへのカプセルの掃引の問い合わせ {
    静止したカプセル: カプセル,
}

impl 静止したカプセルへのカプセルの掃引の問い合わせ {
    /// 触れる相手として静止したカプセルを受け取って保持する。
    pub fn 静止したカプセルから生成する(静止したカプセル: カプセル) -> Self {
        Self { 静止したカプセル }
    }

    /// 掃引したカプセルが静止したカプセルに最初に触れる点を求める。掃引の始まりで既に半径の和以内に居る
    /// カプセルは、動けた割合0で返す。
    pub fn カプセルが静止したカプセルに最初に触れる点を求める(
        &self,
        掃引するカプセル: &形を掃引するカプセル,
    ) -> Result<カプセルが静止したカプセルに最初に触れる点, カプセルの問い合わせエラー> {
        let 求解 = カプセルどうしの接触の求解::生成する(掃引するカプセル, &self.静止したカプセル);
        if let Some(場所) = self.掃引の始まりで触れている場所を求める(&求解)? {
            let 接触 = self.接触を組む(掃引で動けた割合::一歩も動けなかった(), 場所)?;
            return Ok(カプセルが静止したカプセルに最初に触れる点::静止したカプセルに触れる(接触));
        }
        match 求解.掃引の途中で最初に触れる接触を求める()? {
            Some(触れ始める) => Ok(
                カプセルが静止したカプセルに最初に触れる点::静止したカプセルに触れる(
                    self.接触を組む(触れ始める.動けた割合(), 触れ始める.場所())?,
                ),
            ),
            None => Ok(カプセルが静止したカプセルに最初に触れる点::静止したカプセルに触れない),
        }
    }

    // 掃引の始まりで2つの軸の隔たりが半径の和以下なら、そのとき最も近い特徴の場所。軸そのものが相手を貫く経路を
    // 別に置かないのは、2つのカプセルの重なりが軸どうしの隔たりで言い尽くされ、候補がその隔たりを数え上げるためである。
    fn 掃引の始まりで触れている場所を求める(
        &self,
        求解: &カプセルどうしの接触の求解<'_>,
    ) -> Result<Option<静止したカプセルで触れた場所>, カプセルの問い合わせエラー> {
        let Some(最近接) = 求解.掃引の始まりで最も近い特徴を求める()? else {
            return Ok(None);
        };
        if 最近接.隔たりの二乗() <= 求解.半径の和の二乗() {
            return Ok(Some(最近接.場所()));
        }
        Ok(None)
    }

    // 触れた場所から答えを組む。長さが0で向きが定まらないのは2つの軸がちょうど交わる場合であり、
    // カプセルの軸の上の点は代わりに使える外向きを持たないため型付きエラーで返す。
    fn 接触を組む(
        &self,
        動けた割合: 掃引で動けた割合,
        場所: 静止したカプセルで触れた場所,
    ) -> Result<掃引したカプセルの静止したカプセルへの接触, カプセルの問い合わせエラー> {
        let Some(単位変位) = 場所.最近接点から掃引する軸への変位().長さで正した変位を求める() else {
            return Err(カプセルの問い合わせエラー::接触の単位法線が定まらない);
        };
        let 接触位置 = 場所
            .軸の上の最近接点()
            .変位だけ進んだ位置を求める(単位変位.実数倍する(self.静止したカプセル.半径のメートル()))?;
        Ok(掃引したカプセルの静止したカプセルへの接触::生成する(
            動けた割合,
            接触位置,
            単位変位.正した変位を方向へ狭める()?,
            場所.触れた特徴(),
        ))
    }
}
