//! 候補の種類から、その特徴の方程式と最近接の工程を選ぶ振り分け。担当するのは選ぶことだけであり、
//! 式そのものは静止した軸の端と軸の内側の求解が持つ。
//!
//! 振り分けを1箇所へ集めるのは、候補の種類を増やしたときに方程式と最近接の片方だけを足す取りこぼしを
//! 型検査で落とすためである。網羅の`match`が2つ並ぶため、枝を1つ足すと両方が同時にコンパイルで失敗する。

use crate::solver::掃引の2次方程式;

use super::error::カプセルの問い合わせエラー;
use super::sweep_candidate::静止したカプセルとの接触の特徴の候補;
use super::sweep_place::軸と特徴の最近接;
use super::sweep_solver::カプセルどうしの接触の求解;

impl カプセルどうしの接触の求解<'_> {
    // 候補の接触の時刻が満たす方程式。その候補が成り立たない形(長さ0の軸、平行な2直線)では値なしを返す。
    pub(super) fn 候補の方程式を組む(
        &self, 候補: 静止したカプセルとの接触の特徴の候補
    ) -> Option<掃引の2次方程式> {
        match 候補 {
            静止したカプセルとの接触の特徴の候補::静止した軸の端と掃引する軸の端 {
                静止した端, 掃引する端
            } => Some(self.二つの軸の端の方程式を組む(静止した端, 掃引する端)),
            静止したカプセルとの接触の特徴の候補::静止した軸の内側と掃引する軸の端 { 掃引する端 } => {
                self.静止した軸の内側と掃引する軸の端の方程式を組む(掃引する端)
            }
            静止したカプセルとの接触の特徴の候補::静止した軸の端と掃引する軸の内側 { 静止した端 } => {
                self.静止した軸の端と掃引する軸の内側の方程式を組む(静止した端)
            }
            静止したカプセルとの接触の特徴の候補::二つの軸の内側 => self.二つの軸の内側の方程式を組む(),
        }
    }

    // 時刻での、その候補が指す2つの特徴の最近接。媒介変数がどちらかの軸の範囲の外にあるなら値なしを返す。
    pub(super) fn 候補の最近接を求める(
        &self,
        候補: 静止したカプセルとの接触の特徴の候補,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, カプセルの問い合わせエラー> {
        match 候補 {
            静止したカプセルとの接触の特徴の候補::静止した軸の端と掃引する軸の端 {
                静止した端, 掃引する端
            } => Ok(Some(self.二つの軸の端の最近接を求める(静止した端, 掃引する端, 時刻))),
            静止したカプセルとの接触の特徴の候補::静止した軸の内側と掃引する軸の端 { 掃引する端 } => {
                self.静止した軸の内側と掃引する軸の端の最近接を求める(掃引する端, 時刻)
            }
            静止したカプセルとの接触の特徴の候補::静止した軸の端と掃引する軸の内側 { 静止した端 } => {
                Ok(self.静止した軸の端と掃引する軸の内側の最近接を求める(静止した端, 時刻))
            }
            静止したカプセルとの接触の特徴の候補::二つの軸の内側 => self.二つの軸の内側の最近接を求める(時刻),
        }
    }
}
