//! カプセルどうしの接触の求解: 掃引するカプセル1つと静止したカプセル1つを受け取り、「掃引の途中で最初に触れる
//! 接触」と「掃引の始まりで最も近い特徴」の2つに答える操作サービスである。2つのカプセルをコンストラクタで
//! 受け取って保持するため、どの問いの署名にも形が現れない。
//!
//! 2つの問いを1つの型が持つのは、どちらも同じ9通りの候補を同じ順に数え、同じ最近接の工程を通るためである。
//! 掃引の始まりで既に半径の和以内に居るなら動ける割合は0であり、そのときの法線は最も近い特徴から導く。
//! 直方体の掃引の求解と同じ形である。
//!
//! 半径の和はここで1回だけ作る。2つの半径を足す加算が丸めを1回通し、その丸めは接触の隔たりの目標値を最終桁ぶん
//! 動かすため、候補ごとに足し直すと同じ目標値が9通りの綴りを持つことになる。

use crate::shape::{カプセル, 形を掃引するカプセル};
use crate::solver::{掃引で動けた割合, 最も小さい量の候補だけを覚える器};

use super::error::カプセルの問い合わせエラー;
use super::sweep_candidate::静止したカプセルとの接触の特徴の候補;
use super::sweep_place::{触れ始める候補, 軸と特徴の最近接};

pub(super) struct カプセルどうしの接触の求解<'掃引> {
    掃引するカプセル: &'掃引 形を掃引するカプセル,
    静止したカプセル: &'掃引 カプセル,
    半径の和: f64,
}

impl<'掃引> カプセルどうしの接触の求解<'掃引> {
    pub(super) fn 生成する(
        掃引するカプセル: &'掃引 形を掃引するカプセル, 静止したカプセル: &'掃引 カプセル
    ) -> Self {
        Self {
            掃引するカプセル,
            静止したカプセル,
            半径の和: 掃引するカプセル.半径のメートル() + 静止したカプセル.半径のメートル(),
        }
    }

    pub(super) fn 掃引するカプセル(&self) -> &形を掃引するカプセル {
        self.掃引するカプセル
    }

    pub(super) fn 静止したカプセル(&self) -> &カプセル {
        self.静止したカプセル
    }

    pub(super) fn 半径の和(&self) -> f64 {
        self.半径の和
    }

    // 掃引の途中で最初に触れる接触。どの候補も触れないなら値なしを返す。
    pub(super) fn 掃引の途中で最初に触れる接触を求める(
        &self,
    ) -> Result<Option<触れ始める候補>, カプセルの問い合わせエラー> {
        let mut 最小 = 最も小さい量の候補だけを覚える器::まだ何も無い状態から始める();
        for 候補 in 静止したカプセルとの接触の特徴の候補::並べる() {
            if let Some(触れ始める) = self.候補が最初に触れる時刻を求める(候補)? {
                最小.候補を1つ数える(触れ始める.動けた割合().値(), 触れ始める);
            }
        }
        Ok(最小.覚えている候補を取り出す())
    }

    // 掃引の始まりで、掃引するカプセルの軸に最も近い特徴とその隔たり。呼び出し側はこの隔たりを半径の和と比べ、
    // 以下なら動く前から触れていたものとして扱う。
    pub(super) fn 掃引の始まりで最も近い特徴を求める(
        &self,
    ) -> Result<Option<軸と特徴の最近接>, カプセルの問い合わせエラー> {
        let mut 最小 = 最も小さい量の候補だけを覚える器::まだ何も無い状態から始める();
        for 候補 in 静止したカプセルとの接触の特徴の候補::並べる() {
            if let Some(最近接) = self.候補の最近接を求める(候補, 0.0)? {
                最小.候補を1つ数える(最近接.隔たりの二乗(), 最近接);
            }
        }
        Ok(最小.覚えている候補を取り出す())
    }

    // 1つの候補について、掃引の中に在る最小の根を探す。根を割合として受理するのは`掃引で動けた割合`であり、
    // 端をわずかに越えた根はそこで端の正準値へ寄る。寄せた割合で最近接を求め直し、媒介変数が2つの軸の範囲に
    // 収まったときだけ候補にする。収まらない根は、軸より広がった直線での接触であり、実際には触れていない。
    fn 候補が最初に触れる時刻を求める(
        &self,
        候補: 静止したカプセルとの接触の特徴の候補,
    ) -> Result<Option<触れ始める候補>, カプセルの問い合わせエラー> {
        let Some(方程式) = self.候補の方程式を組む(候補) else {
            return Ok(None);
        };
        for 根 in 方程式.根を小さい順に並べる() {
            let Some(動けた割合) = 掃引で動けた割合::根を端へ寄せて受理する(根) else {
                continue;
            };
            if let Some(最近接) = self.候補の最近接を求める(候補, 動けた割合.値())? {
                return Ok(Some(触れ始める候補::生成する(動けた割合, 最近接.場所())));
            }
        }
        Ok(None)
    }
}
