//! 静止したカプセルの軸の内側に触れる2つの候補の求解。触れる相手が円筒の側面であるから、接触の位置は軸の上の
//! 比が決める点になる。
//!
//! 掃引する軸の端との組は、固定の直線と動く球の隔たりが半径の和に等しくなる条件である。隔たりの二乗は
//! 「直線の1点から球の中心への変位と直線の変位の外積」の長さの二乗を直線の長さの二乗で割ったものであるから、
//! 分母を払うと時刻の2次方程式になる。直線は軸より長いため、根の時刻で最近接点が静止した軸の内側に収まることを
//! 確かめる。収まらない接触は静止した軸の端の候補が答える。
//!
//! 内側どうしの組は、ねじれの位置にある2直線どうしが半径の和だけ離れて並ぶ時刻を解く。隔たりは両方に垂直な向き
//! (2つの変位の外積)へ射影した長さであり、射影は時刻の1次式であるから平面と球と同じ形へ帰着する。2つの軸が
//! 平行なとき外積は零になって隔たりが定まらないため、この候補を数えない。平行な場合の最も早い接触は端の候補が
//! 同じ時刻で答える。直線は軸より長いため、根の時刻で2つの最近接点がそれぞれの軸の内側に収まることを確かめる。

use crate::shape::形の局所座標の変位;
use crate::solver::{二つの直線の最近接の媒介変数, 掃引の2次方程式, 軸の端};

use super::error::カプセルの問い合わせエラー;
use super::feature::静止したカプセルで触れた特徴;
use super::sweep_place::{軸と特徴の最近接, 静止したカプセルで触れた場所};
use super::sweep_solver::カプセルどうしの接触の求解;

impl カプセルどうしの接触の求解<'_> {
    // 静止した軸の長さが0のカプセル(球)には内側が無いため値なしを返す。
    pub(super) fn 静止した軸の内側と掃引する軸の端の方程式を組む(
        &self, 掃引する端: 軸の端
    ) -> Option<掃引の2次方程式> {
        let 静止した軸 = self.静止した軸の変位();
        let 静止した軸の長さの二乗 = 静止した軸.長さの二乗();
        if 静止した軸の長さの二乗 <= 0.0 {
            return None;
        }
        Some(掃引の2次方程式::直線と球の隔たりから組む(
            self.静止した点から時刻の掃引する軸の端への変位(self.静止した軸の始点の位置(), 掃引する端, 0.0),
            self.掃引の変位(),
            静止した軸,
            静止した軸の長さの二乗,
            self.半径の和の二乗(),
        ))
    }

    pub(super) fn 静止した軸の内側と掃引する軸の端の最近接を求める(
        &self,
        掃引する端: 軸の端,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, カプセルの問い合わせエラー> {
        let 静止した軸 = self.静止した軸の変位();
        let 静止した軸の長さの二乗 = 静止した軸.長さの二乗();
        if 静止した軸の長さの二乗 <= 0.0 {
            return Ok(None);
        }
        let 始点から軸へ = self.静止した点から時刻の掃引する軸の端への変位(self.静止した軸の始点の位置(), 掃引する端, 時刻);
        let 静止した軸の比 = 始点から軸へ.内積(静止した軸) / 静止した軸の長さの二乗;
        if !(0.0..=1.0).contains(&静止した軸の比) {
            return Ok(None);
        }
        let 最近接点から軸へ = 始点から軸へ.引く(静止した軸.実数倍する(静止した軸の比));
        Ok(Some(self.静止した軸の内側に触れた最近接を組む(
            静止した軸の比,
            最近接点から軸へ,
        )?))
    }

    pub(super) fn 二つの軸の内側の方程式を組む(&self) -> Option<掃引の2次方程式> {
        掃引の2次方程式::二つの直線の隔たりから組む(
            self.静止した点から時刻の掃引する軸の端への変位(self.静止した軸の始点の位置(), 軸の端::始点の側, 0.0),
            self.掃引の変位(),
            self.掃引する軸の変位(),
            self.静止した軸の変位(),
            self.半径の和の二乗(),
        )
    }

    pub(super) fn 二つの軸の内側の最近接を求める(
        &self,
        時刻: f64,
    ) -> Result<Option<軸と特徴の最近接>, カプセルの問い合わせエラー> {
        let 掃引する軸 = self.掃引する軸の変位();
        let 静止した軸 = self.静止した軸の変位();
        let 始点から始点へ =
            self.静止した点から時刻の掃引する軸の端への変位(self.静止した軸の始点の位置(), 軸の端::始点の側, 時刻);
        let Some(媒介変数) =
            二つの直線の最近接の媒介変数::両方の範囲に収まる組を求める(掃引する軸, 静止した軸, 始点から始点へ)
        else {
            return Ok(None);
        };
        let 最近接点から軸へ = 始点から始点へ
            .加える(掃引する軸.実数倍する(媒介変数.第1の直線の比()))
            .引く(静止した軸.実数倍する(媒介変数.第2の直線の比()));
        Ok(Some(self.静止した軸の内側に触れた最近接を組む(
            媒介変数.第2の直線の比(),
            最近接点から軸へ,
        )?))
    }

    // 静止した軸の上の1点に触れた最近接を組む。最近接点は軸の始点から軸の変位を比の分だけ進めた点である。
    fn 静止した軸の内側に触れた最近接を組む(
        &self,
        静止した軸の比: f64,
        最近接点から軸へ: 形の局所座標の変位,
    ) -> Result<軸と特徴の最近接, カプセルの問い合わせエラー> {
        let 最近接点 = self
            .静止した軸の始点の位置()
            .変位だけ進んだ位置を求める(self.静止した軸の変位().実数倍する(静止した軸の比))?;
        Ok(軸と特徴の最近接::生成する(
            最近接点から軸へ.長さの二乗(),
            静止したカプセルで触れた場所::生成する(最近接点, 最近接点から軸へ, 静止したカプセルで触れた特徴::軸の内側の側面),
        ))
    }
}
