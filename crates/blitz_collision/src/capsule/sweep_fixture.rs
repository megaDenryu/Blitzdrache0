//! カプセルどうしの掃引の反証が共有する材料。2つのカプセルを組む入口と、答えから接触を取り出す読み取りを持つ。
//!
//! 期待値をすべて手で書けるように、反証は軸に沿った姿勢と半径1を基本に組む。回った姿勢の答えは、
//! 相手が任意姿勢の直方体である反証が既に見ている。

use blitz_math::{ローカル, 方向};

use crate::shape::{カプセル, 形の局所座標の位置, 形の局所座標の変位, 形を掃引するカプセル};

use super::error::カプセルの問い合わせエラー;
use super::sweep_contact::{
    カプセルが静止したカプセルに最初に触れる点, 掃引したカプセルの静止したカプセルへの接触
};
use super::sweep_query::静止したカプセルへのカプセルの掃引の問い合わせ;

// 位置と割合の比較に許す幅。根が2進で割り切れない組でも、時刻から位置を組み直す誤差はこの幅に収まる。
pub(super) const 掃引の反証が許す幅: f64 = 1.0e-12;

pub(super) fn 局所の点(成分: [f64; 3]) -> 形の局所座標の位置 {
    match 形の局所座標の位置::生成する(成分[0], 成分[1], 成分[2]) {
        Ok(位置) => 位置,
        Err(誤り) => panic!("試験用の局所の点を作れなかった: {誤り}"),
    }
}

pub(super) fn 局所の変位(成分: [f64; 3]) -> 形の局所座標の変位 {
    match 形の局所座標の変位::生成する(成分[0], 成分[1], 成分[2]) {
        Ok(変位) => 変位,
        Err(誤り) => panic!("試験用の局所の変位を作れなかった: {誤り}"),
    }
}

pub(super) fn 静止したカプセルを作る(軸の始点: [f64; 3], 軸の終点: [f64; 3], 半径: f64) -> カプセル {
    match カプセル::生成する(局所の点(軸の始点), 局所の点(軸の終点), 半径) {
        Ok(カプセル) => カプセル,
        Err(誤り) => panic!("試験用の静止したカプセルを作れなかった: {誤り}"),
    }
}

pub(super) fn 掃引するカプセルを作る(
    軸の始点: [f64; 3],
    軸の終点: [f64; 3],
    半径: f64,
    掃引の変位: [f64; 3],
) -> 形を掃引するカプセル {
    match 形を掃引するカプセル::生成する(局所の点(軸の始点), 局所の点(軸の終点), 半径, 局所の変位(掃引の変位))
    {
        Ok(カプセル) => カプセル,
        Err(誤り) => panic!("試験用の掃引するカプセルを作れなかった: {誤り}"),
    }
}

pub(super) fn 触れる点を求める(
    静止した: &カプセル,
    掃引する: &形を掃引するカプセル,
) -> Result<カプセルが静止したカプセルに最初に触れる点, カプセルの問い合わせエラー> {
    静止したカプセルへのカプセルの掃引の問い合わせ::静止したカプセルから生成する(*静止した)
        .カプセルが静止したカプセルに最初に触れる点を求める(掃引する)
}

pub(super) fn 触れる点を確かめて求める(
    静止した: &カプセル,
    掃引する: &形を掃引するカプセル,
) -> カプセルが静止したカプセルに最初に触れる点 {
    match 触れる点を求める(静止した, 掃引する) {
        Ok(答え) => 答え,
        Err(誤り) => panic!("カプセルどうしの掃引の問い合わせが失敗した: {誤り}"),
    }
}

pub(super) fn 接触を取り出す(
    答え: カプセルが静止したカプセルに最初に触れる点,
) -> 掃引したカプセルの静止したカプセルへの接触 {
    match 答え {
        カプセルが静止したカプセルに最初に触れる点::静止したカプセルに触れる(接触) => 接触,
        カプセルが静止したカプセルに最初に触れる点::静止したカプセルに触れない => {
            panic!("触れるはずのカプセルが触れなかった")
        }
    }
}

pub(super) fn 位置の成分(位置: 形の局所座標の位置) -> [f64; 3] {
    [位置.xのメートル(), 位置.yのメートル(), 位置.zのメートル()]
}

pub(super) fn 方向の成分(方向: 方向<ローカル>) -> [f32; 3] {
    [方向.x(), 方向.y(), 方向.z()]
}

pub(super) fn 三成分が近いことを確かめる(実測: [f64; 3], 期待: [f64; 3], 何の値か: &str) {
    for 軸 in 0usize..3 {
        assert!(
            (実測[軸] - 期待[軸]).abs() <= 掃引の反証が許す幅,
            "{何の値か}の軸{軸}が期待から離れている(実測{}、期待{})",
            実測[軸],
            期待[軸]
        );
    }
}
