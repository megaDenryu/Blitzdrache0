//! 静止したカプセルへの詳細判定で破れる条件。
//!
//! 形そのものの破れ(半径が正の有限でない等)はここに入らない。それは`カプセルの生成エラー`が持ち、形を作る
//! 地点で拒まれている。ここに在るのは求解が導く値の破れである。

use blitz_math::方向エラー;
use thiserror::Error;

use crate::shape::形の局所座標の生成エラー;
use crate::solver::無次元の媒介変数の生成エラー;

/// 静止したカプセルへの詳細判定で破れる条件。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum カプセルの問い合わせエラー {
    /// 求解が導いた最近接の点や接触の点を、局所座標の位置として作れなかった。
    #[error("カプセルへの問い合わせの点を作れない: {0}")]
    問い合わせの点を作れない(#[from] 形の局所座標の生成エラー),
    /// 掃引で動けた割合が、0以上1以下の有限値でなかった。
    #[error("カプセルへの問い合わせの媒介変数を作れない: {0}")]
    問い合わせの媒介変数を作れない(#[from] 無次元の媒介変数の生成エラー),
    /// 求めた接触の向きを単位方向へ狭められなかった。
    #[error("カプセルへの接触の単位法線を作れない: {0}")]
    接触の単位法線を作れない(#[from] 方向エラー),
    /// 2つの軸がちょうど交わって隔たりが0になり、押し戻す向きが定まらなかった。
    #[error("2つのカプセルの軸が交わっており接触の単位法線が定まらない")]
    接触の単位法線が定まらない,
}
