//! 掃引したカプセルが、静止したカプセルのどの部分に触れたか。
//!
//! 区別を残すのは、接触の位置がどう決まるかが2つで違うためである。端の半球に触れたときの接触点は軸の端から
//! 半径だけ離れた点であり、内側の側面に触れたときの接触点は軸の内側の1点から半径だけ離れた点である。
//!
//! 掃引した側のどの部分が触れたかは答えに含めない。直方体と三角形の掃引が同じ形で相手の側の特徴だけを返して
//! おり、受け取る側が読む向きは「何に触れたか」であって「自分のどこで触れたか」ではないためである。

use crate::solver::軸の端;

/// 掃引したカプセルが、静止したカプセルのどの部分に触れたか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 静止したカプセルで触れた特徴 {
    /// 軸の端に置いた半球に触れた。
    軸の端の半球(軸の端),
    /// 2つの半球をつなぐ円筒の側面、すなわち軸の内側に触れた。
    軸の内側の側面,
}
