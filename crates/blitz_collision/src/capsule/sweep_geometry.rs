//! 掃引の求解が特徴ごとの式を組むときに何度も使う幾何の読み替え。触れるのは保持した2つのカプセルだけである。
//!
//! この工程を分けるのは、静止した軸の端に触れる求解と内側に触れる求解の2つが同じ読み替えを使うためである。
//! 読み替えをそれぞれの求解へ写すと、時刻での軸の位置の作り方が2つに分かれ、同じ時刻で違う位置を指す余地が生まれる。

use crate::shape::{形の局所座標の位置, 形の局所座標の変位};
use crate::solver::軸の端;

use super::sweep_solver::カプセルどうしの接触の求解;

impl カプセルどうしの接触の求解<'_> {
    pub(super) fn 半径の和の二乗(&self) -> f64 {
        self.半径の和() * self.半径の和()
    }

    pub(super) fn 掃引の変位(&self) -> 形の局所座標の変位 {
        self.掃引するカプセル().掃引の変位()
    }

    // 掃引する軸の始点から終点へ向かう変位。長さ0の軸(球)では零になる。
    pub(super) fn 掃引する軸の変位(&self) -> 形の局所座標の変位 {
        self.掃引するカプセル().軸の変位を求める()
    }

    // 静止した軸の始点から終点へ向かう変位。長さ0の軸(球)では零になる。
    pub(super) fn 静止した軸の変位(&self) -> 形の局所座標の変位 {
        self.静止したカプセル().軸の変位を求める()
    }

    pub(super) fn 静止した軸の始点の位置(&self) -> 形の局所座標の位置 {
        self.静止したカプセル().軸の始点()
    }

    pub(super) fn 静止した軸の端の位置(&self, 端: 軸の端) -> 形の局所座標の位置 {
        self.静止したカプセル().軸の端点を並べる()[端.並びの位置()]
    }

    // 掃引の始まりでの、掃引する軸の端の位置。
    pub(super) fn 掃引する軸の端の位置(&self, 端: 軸の端) -> 形の局所座標の位置 {
        self.掃引するカプセル().軸の端点を並べる()[端.並びの位置()]
    }

    // 静止したカプセルの上の基準の点から、時刻での掃引する軸の端へ向かう変位。掃引はカプセル全体を同じだけ
    // 動かすため、時刻の1次式である。
    pub(super) fn 静止した点から時刻の掃引する軸の端への変位(
        &self,
        基準の点: 形の局所座標の位置,
        端: 軸の端,
        時刻: f64,
    ) -> 形の局所座標の変位 {
        基準の点
            .終点までの変位を求める(self.掃引する軸の端の位置(端))
            .加える(self.掃引の変位().実数倍する(時刻))
    }
}
