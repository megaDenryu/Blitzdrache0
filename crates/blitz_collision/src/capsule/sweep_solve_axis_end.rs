//! 静止したカプセルの軸の端に触れる2つの候補の求解。触れる相手が半球であるから、接触の位置も特徴も軸の端が決める。
//!
//! 掃引する軸の端との組は、固定の点と動く球の隔たりが半径の和に等しくなる条件であり、制約が無い。球はカプセルの
//! 一部であるから、この根はどれも実際に触れている時刻である。
//!
//! 掃引する軸の内側との組は、固定の点から動く直線までの隔たりが半径の和に等しくなる条件である。掃引の変位を
//! 逆向きにして渡すのは、動く直線の側から見ると固定の点がその逆向きに動くためであり、これで固定の直線と動く球の
//! 式がそのまま使える。逆向きにする実数倍は符号を反転するだけであるから丸めを1つも入れない。直線は軸より
//! 長いため、根の時刻で最近接点が掃引する軸の内側に収まることを確かめる。収まらない接触は軸の端の候補が答える。

use crate::shape::形の局所座標の変位;
use crate::solver::{掃引の2次方程式, 軸の端};

use super::feature::静止したカプセルで触れた特徴;
use super::sweep_place::{軸と特徴の最近接, 静止したカプセルで触れた場所};
use super::sweep_solver::カプセルどうしの接触の求解;

impl カプセルどうしの接触の求解<'_> {
    pub(super) fn 二つの軸の端の方程式を組む(&self, 静止した端: 軸の端, 掃引する端: 軸の端) -> 掃引の2次方程式 {
        掃引の2次方程式::点と球の隔たりから組む(
            self.静止した点から時刻の掃引する軸の端への変位(self.静止した軸の端の位置(静止した端), 掃引する端, 0.0),
            self.掃引の変位(),
            self.半径の和の二乗(),
        )
    }

    pub(super) fn 二つの軸の端の最近接を求める(
        &self, 静止した端: 軸の端, 掃引する端: 軸の端, 時刻: f64
    ) -> 軸と特徴の最近接 {
        let 端から軸へ =
            self.静止した点から時刻の掃引する軸の端への変位(self.静止した軸の端の位置(静止した端), 掃引する端, 時刻);
        self.静止した軸の端に触れた最近接を組む(静止した端, 端から軸へ)
    }

    // 掃引する軸の長さが0のカプセル(球)には内側が無いため値なしを返す。
    pub(super) fn 静止した軸の端と掃引する軸の内側の方程式を組む(
        &self, 静止した端: 軸の端
    ) -> Option<掃引の2次方程式> {
        let 掃引する軸 = self.掃引する軸の変位();
        let 掃引する軸の長さの二乗 = 掃引する軸.長さの二乗();
        if 掃引する軸の長さの二乗 <= 0.0 {
            return None;
        }
        Some(掃引の2次方程式::直線と球の隔たりから組む(
            self.掃引する軸の端の位置(軸の端::始点の側)
                .終点までの変位を求める(self.静止した軸の端の位置(静止した端)),
            self.掃引の変位().実数倍する(-1.0),
            掃引する軸,
            掃引する軸の長さの二乗,
            self.半径の和の二乗(),
        ))
    }

    // 時刻での、静止した軸の端と掃引する軸の直線の最近接。最近接点が掃引する軸の外にあるなら値なしを返す。
    pub(super) fn 静止した軸の端と掃引する軸の内側の最近接を求める(
        &self,
        静止した端: 軸の端,
        時刻: f64,
    ) -> Option<軸と特徴の最近接> {
        let 掃引する軸 = self.掃引する軸の変位();
        let 掃引する軸の長さの二乗 = 掃引する軸.長さの二乗();
        if 掃引する軸の長さの二乗 <= 0.0 {
            return None;
        }
        let 端から始点へ =
            self.静止した点から時刻の掃引する軸の端への変位(self.静止した軸の端の位置(静止した端), 軸の端::始点の側, 時刻);
        let 掃引する軸の比 = -端から始点へ.内積(掃引する軸) / 掃引する軸の長さの二乗;
        if !(0.0..=1.0).contains(&掃引する軸の比) {
            return None;
        }
        Some(self.静止した軸の端に触れた最近接を組む(静止した端, 端から始点へ.加える(掃引する軸.実数倍する(掃引する軸の比))))
    }

    fn 静止した軸の端に触れた最近接を組む(
        &self, 静止した端: 軸の端, 端から軸へ: 形の局所座標の変位
    ) -> 軸と特徴の最近接 {
        軸と特徴の最近接::生成する(
            端から軸へ.長さの二乗(),
            静止したカプセルで触れた場所::生成する(
                self.静止した軸の端の位置(静止した端),
                端から軸へ,
                静止したカプセルで触れた特徴::軸の端の半球(静止した端),
            ),
        )
    }
}
