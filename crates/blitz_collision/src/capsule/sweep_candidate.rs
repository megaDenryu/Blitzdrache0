//! 接触の特徴の候補: 掃引するカプセルのどの部分が、静止したカプセルのどの部分に触れるかの組み合わせである。
//! 掃引の求解は、4種類を数え上げた9通りの候補を1つずつ数え、それぞれの接触の時刻を解いて最小を選ぶ。
//!
//! 4種類で足りる根拠は、最初に触れた瞬間の最近接点の対にある。どちらのカプセルでも最近接点は軸の2つの端か
//! 軸の内側のどれかであるから、種類の組み合わせは3かける3の9つであり、これを静止した側の端が2つあることで
//! 展開すると9通りになる。内訳は、端と端で4、静止した軸の内側と掃引する軸の端で2、静止した軸の端と掃引する
//! 軸の内側で2、内側どうしで1である。
//!
//! 直方体や三角形の掃引が数えなかった「軸の内側と面の内側」に当たる組はここに存在しない。カプセルには面が
//! 無く、相手の特徴が端と内側の2つしか無いためである。したがってこの9通りに除外は1つも無い。
//!
//! 内側どうしの組は、2つの軸が平行なときだけ隔たりが定まらない。平行な2直線は共通の垂線を1本に定めないためで
//! あり、そのとき方程式を組む工程が値なしを返す。平行な場合の最も早い接触は端の候補が同じ時刻で答える。
//! 2つの軸が平行なら、内側どうしが最も近づく瞬間には必ず、どちらかの軸の端も同じ隔たりに達しているからである。
//!
//! どの候補も、直線という軸より広がった形での接触を解くため、根の時刻で媒介変数が軸の範囲に収まることを
//! 確かめる。収まる根はどれも実際に触れている時刻であるから、最初に触れる時刻より早くはなりえない。
//! したがって候補ごとに範囲を満たす最小の根を取り、その最小を選べば答えになる。

use crate::solver::軸の端;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 静止したカプセルとの接触の特徴の候補 {
    静止した軸の端と掃引する軸の端 {
        静止した端: 軸の端,
        掃引する端: 軸の端,
    },
    静止した軸の内側と掃引する軸の端 {
        掃引する端: 軸の端,
    },
    静止した軸の端と掃引する軸の内側 {
        静止した端: 軸の端,
    },
    二つの軸の内側,
}

impl 静止したカプセルとの接触の特徴の候補 {
    // 9通りの候補を、求解が数える順に並べる。並びを固定するのは、接触の時刻が並んだときにどの特徴の
    // 答えを返すかまで入力だけで決まるようにするためである。
    pub(super) fn 並べる() -> impl Iterator<Item = Self> {
        let 掃引する端ごと = 軸の端::並べる().into_iter().flat_map(|掃引する端| {
            let 端どうし =
                軸の端::並べる().into_iter().map(move |静止した端| Self::静止した軸の端と掃引する軸の端 {
                    静止した端, 掃引する端
                });
            端どうし.chain([Self::静止した軸の内側と掃引する軸の端 { 掃引する端 }])
        });
        掃引する端ごと
            .chain(
                軸の端::並べる()
                    .into_iter()
                    .map(|静止した端| Self::静止した軸の端と掃引する軸の内側 { 静止した端 }),
            )
            .chain([Self::二つの軸の内側])
    }
}
