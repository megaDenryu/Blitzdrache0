//! 掃引したカプセルが静止したカプセルに最初に触れた点と、触れなかったことを表す枝。
//!
//! 接触が持つのは幾何学的な事実だけであり、そこで止まるか滑るか跳ねるかという意味付けは持たない。
//!
//! 動けた割合と接触位置は同じ1つの時刻から導いている。接触位置は静止したカプセルの表面の点であり、
//! その時刻の掃引したカプセルの表面もその点を通る。2つの軸の隔たりが半径の和に等しい瞬間、軸を結ぶ線分の上で
//! 静止した側の半径だけ進んだ点は、掃引した側の軸からも掃引した側の半径だけ離れているためである。
//!
//! 掃引の始まりで既に重なっていた場合だけ、接触位置は2つの表面が実際に出会う点ではない。そのときの隔たりは
//! 半径の和より小さく、返すのは静止したカプセルの表面のうち相手の軸に最も近い点である。直方体の掃引が
//! 始まりの重なりで最も近い表面の点を返すのと同じ様式である。

use blitz_math::{ローカル, 方向};

use crate::shape::形の局所座標の位置;
use crate::solver::掃引で動けた割合;

use super::feature::静止したカプセルで触れた特徴;

/// 掃引したカプセルが静止したカプセルに最初に触れた点。変位の全体を動いても触れなかった枝と、触れた接触を持つ枝の2つである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum カプセルが静止したカプセルに最初に触れる点 {
    /// 変位の全体を動いても静止したカプセルに触れなかった。
    静止したカプセルに触れない,
    /// 変位の途中で静止したカプセルに触れ、その最初の接触を持つ。
    静止したカプセルに触れる(掃引したカプセルの静止したカプセルへの接触),
}

/// 掃引したカプセルが静止したカプセルへ触れた1つの事実。動けた割合・接触位置・接触の単位法線・触れた特徴を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 掃引したカプセルの静止したカプセルへの接触 {
    動けた割合: 掃引で動けた割合,
    接触位置: 形の局所座標の位置,
    接触の単位法線: 方向<ローカル>,
    触れた特徴: 静止したカプセルで触れた特徴,
}

impl 掃引したカプセルの静止したカプセルへの接触 {
    pub(super) fn 生成する(
        動けた割合: 掃引で動けた割合,
        接触位置: 形の局所座標の位置,
        接触の単位法線: 方向<ローカル>,
        触れた特徴: 静止したカプセルで触れた特徴,
    ) -> Self {
        Self {
            動けた割合,
            接触位置,
            接触の単位法線,
            触れた特徴,
        }
    }

    /// 掃引の変位のうち、静止したカプセルに触れるまでに動けた分の割合。動く前から触れていた場合は0である。
    pub fn 動けた割合(&self) -> 掃引で動けた割合 {
        self.動けた割合
    }

    /// 静止したカプセルの表面の上の接触点。その時刻の掃引したカプセルの表面もこの点を通る。
    pub fn 接触位置(&self) -> 形の局所座標の位置 {
        self.接触位置
    }

    /// 静止したカプセルの軸から、掃引したカプセルの軸へ向かう単位方向。接触位置での外向きの法線でもある。
    pub fn 接触の単位法線(&self) -> 方向<ローカル> {
        self.接触の単位法線
    }

    /// 静止したカプセルの軸の端の半球と内側の側面のどちらに触れたか。
    pub fn 触れた特徴(&self) -> 静止したカプセルで触れた特徴 {
        self.触れた特徴
    }
}
