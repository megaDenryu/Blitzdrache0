//! 対称性の反証。無作為に散らした動くカプセルの対について、どちらを静止させる側に選んでも触れるかどうかと
//! 触れる時刻と触れる場所が一致し、法線が逆向きになることを見る。
//!
//! これが還元の等価の総当たり的な反証である。還元は対の一方を静止させて相手に差を与えるため、選び方を入れ替えると
//! 相対変位の符号が反転し、候補の並びも入れ替わる。それでも同じ時刻が出ることは、答えが選び方ではなく2つの
//! 動きの差だけで決まっていることを示す。
//!
//! 接触の位置も、進んだ割合が0より大きい対では選び方に依らない。その対は接触の瞬間にちょうど触れており、
//! 2つの表面が同じ1点で出会うためである。始まりから重なっている対(割合が0の対)では2つの表面が出会わず、
//! それぞれ相手の軸に最も近い自分の表面の点を返すので位置は一致しない。したがって位置の一致は割合が0より
//! 大きい対だけで見る。法線は選び方で符号が反転するため、和が零になることで見る。
//!
//! 位置の比較に許す幅を割合の幅より広く取るのは、2つの位置が別の式から組まれるためである。片方は静止させた
//! 側の軸の上の点から半径だけ進めた点、もう片方は相手の軸の上の点から相手の半径だけ進めた点であり、
//! 根の誤差がそれぞれの経路で位置へ伝わる。

use crate::pseudo_random_fixture::決まった種から進む擬似乱数;
use crate::shape::形を掃引するカプセル;

use super::contact::動く形どうしが最初に触れる点;
use super::pair_fixture::{
    カプセルの対の接触を確かめて求める, 位置の成分, 動くカプセルを作る, 対の反証が許す幅, 方向の成分
};

// 2つの経路で組んだ接触位置の食い違いに許す幅。座標の大きさが10メートルの桁であるため、割合の幅より広く取る。
const 位置の反証が許す幅: f64 = 1.0e-9;

// 無作為の対を作る範囲。半径に対して十分近い距離へ散らし、触れる対と触れない対の両方が出るようにする。
const 軸の端の範囲: f64 = 3.5;
const 変位の範囲: f64 = 8.0;

#[test]
fn どちらを静止させても触れるかどうかと時刻と場所が一致する() {
    let mut 乱数 = 決まった種から進む擬似乱数::種から始める(913);
    let mut 触れた件数 = 0usize;
    for _ in 0..2000 {
        let 第1 = 無作為の動くカプセルを作る(&mut 乱数);
        let 第2 = 無作為の動くカプセルを作る(&mut 乱数);
        let 第1を掃引した答え = カプセルの対の接触を確かめて求める(&第1, &第2);
        let 第2を掃引した答え = カプセルの対の接触を確かめて求める(&第2, &第1);
        match (第1を掃引した答え, 第2を掃引した答え) {
            (動く形どうしが最初に触れる点::二つの形が触れる(第1の接触), 動く形どうしが最初に触れる点::二つの形が触れる(第2の接触)) =>
            {
                触れた件数 += 1;
                let 割合の差 = 第1の接触.触れるまでに進んだ割合().値() - 第2の接触.触れるまでに進んだ割合().値();
                assert!(
                    割合の差.abs() <= 対の反証が許す幅,
                    "静止させる側の選び方で時刻が食い違った({}と{})",
                    第1の接触.触れるまでに進んだ割合().値(),
                    第2の接触.触れるまでに進んだ割合().値()
                );
                let 第1の位置 = 位置の成分(第1の接触.接触位置());
                let 第2の位置 = 位置の成分(第2の接触.接触位置());
                let 第1の向き = 方向の成分(第1の接触.接触の単位法線());
                let 第2の向き = 方向の成分(第2の接触.接触の単位法線());
                for 軸 in 0usize..3 {
                    assert!(
                        (第1の向き[軸] + 第2の向き[軸]).abs() <= 1.0e-6,
                        "静止させる側の選び方で法線が逆向きにならなかった({第1の向き:?}と{第2の向き:?})"
                    );
                    if 第1の接触.触れるまでに進んだ割合().値() > 0.0 {
                        assert!(
                            (第1の位置[軸] - 第2の位置[軸]).abs() <= 位置の反証が許す幅,
                            "静止させる側の選び方で接触位置が食い違った({第1の位置:?}と{第2の位置:?})"
                        );
                    }
                }
            }
            (動く形どうしが最初に触れる点::二つの形は触れない, 動く形どうしが最初に触れる点::二つの形は触れない) =>
                {}
            (第1を掃引した答え, 第2を掃引した答え) => {
                panic!("静止させる側の選び方で触れるかどうかが食い違った({第1を掃引した答え:?}と{第2を掃引した答え:?})")
            }
        }
    }
    assert!(触れた件数 > 300, "触れる対が少なすぎて対称性を試せていない(実測{触れた件数}件)");
}

fn 無作為の動くカプセルを作る(乱数: &mut 決まった種から進む擬似乱数) -> 形を掃引するカプセル {
    let 始点 = 無作為の三成分を作る(乱数, 軸の端の範囲);
    let 軸 = 無作為の三成分を作る(乱数, 2.0);
    動くカプセルを作る(
        始点,
        [始点[0] + 軸[0], 始点[1] + 軸[1], 始点[2] + 軸[2]],
        乱数.範囲の中の値(0.2, 1.5),
        無作為の三成分を作る(乱数, 変位の範囲),
    )
}

fn 無作為の三成分を作る(乱数: &mut 決まった種から進む擬似乱数, 範囲: f64) -> [f64; 3] {
    [
        乱数.範囲の中の値(-範囲, 範囲),
        乱数.範囲の中の値(-範囲, 範囲),
        乱数.範囲の中の値(-範囲, 範囲),
    ]
}
