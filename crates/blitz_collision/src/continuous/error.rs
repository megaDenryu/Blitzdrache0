//! 動く形の対への問い合わせで破れる条件。
//!
//! 形そのものの破れはここに入らない。それぞれの形の生成が拒んでいる。ここに在るのは、還元が作る相対変位と
//! 接触の時刻の位置の破れ、および写した先の片側の掃引が返す失敗である。
//!
//! 相対変位と接触の時刻の位置を別の枝にするのは、どちらも同じ`形の局所座標の生成エラー`を包むが、破れた場所が
//! 入力の側(2つの変位の差が上限を越えた)と答えの側(位置が有限でなくなった)で違うためである。1つの枝へ畳むと、
//! 呼び出し側が入力を直せばよいのか答えを捨てるべきなのかを区別できない。

use thiserror::Error;

use crate::capsule::カプセルの問い合わせエラー;
use crate::oriented_box::直方体の問い合わせエラー;
use crate::shape::形の局所座標の生成エラー;

/// 動く形の対への問い合わせが拒否する理由。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 動く形の対の問い合わせエラー {
    /// 2つの変位の差を、形の座標の絶対値の上限に収まる相対変位として作れなかった。
    #[error("動く形の対の相対変位を作れない: {0}")]
    相対変位を作れない(形の局所座標の生成エラー),
    /// 静止させた側の点を、実際に触れた瞬間の位置へ戻せなかった。
    #[error("動く形の対の接触の時刻の位置を作れない: {0}")]
    接触の時刻の位置を作れない(形の局所座標の生成エラー),
    /// 静止させたカプセルへ写した片側の掃引が答えを作れなかった。
    #[error("静止させたカプセルへの掃引が失敗した: {0}")]
    静止させたカプセルへの掃引が失敗した(#[from] カプセルの問い合わせエラー),
    /// 静止させた直方体へ写した片側の掃引が答えを作れなかった。
    #[error("静止させた直方体への掃引が失敗した: {0}")]
    静止させた直方体への掃引が失敗した(#[from] 直方体の問い合わせエラー),
}
