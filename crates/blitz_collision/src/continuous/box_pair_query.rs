//! 動く直方体への動くカプセルの接触の問い合わせ: 平行移動するカプセルと平行移動する任意姿勢の直方体が最初に
//! 触れる時刻と場所を求める操作サービス。直方体の側を静止させる側としてコンストラクタで受け取る。
//!
//! 直方体を静止させる側に固定するのは、静止させた側だけが回転を持ちうるためではなく、掃引の詳細判定が
//! 「動くカプセルと静止した直方体」の形でしか存在しないためである。この向きなら既存の掃引をそのまま呼べる。
//!
//! 新しい幾何の数学をここに書かない。担当は、還元で相対変位を作り、掃引の変位を差し替えたカプセルを静止させた
//! 直方体へ投げ、返った接触の位置を実際に触れた瞬間へ戻すことだけである。

use crate::oriented_box::{
    カプセルが直方体に最初に触れる点, 直方体で当たった特徴, 直方体のカプセルの掃引の問い合わせ
};
use crate::shape::{動く任意姿勢の直方体, 形の局所座標の変位, 形を掃引するカプセル};

use super::contact::{動く形どうしが最初に触れる点, 動く形どうしの接触};
use super::error::動く形の対の問い合わせエラー;
use super::reduction::動く形の対を片側の掃引へ写す還元;

/// 動く直方体への動くカプセルの接触の問い合わせ。静止させる側の直方体とその変位を保持する操作サービスである。
pub struct 動く直方体への動くカプセルの接触の問い合わせ {
    静止させた形への掃引の問い合わせ: 直方体のカプセルの掃引の問い合わせ,
    静止させる側の変位: 形の局所座標の変位,
}

impl 動く直方体への動くカプセルの接触の問い合わせ {
    /// 動く直方体を静止させる側として受け取り、その形の掃引の問い合わせと変位を保持する。
    pub fn 静止させる側の直方体から生成する(静止させる側の直方体: &動く任意姿勢の直方体) -> Self {
        Self {
            静止させた形への掃引の問い合わせ: 直方体のカプセルの掃引の問い合わせ::直方体から生成する(
                &静止させる側の直方体.直方体(),
            ),
            静止させる側の変位: 静止させる側の直方体.平行移動の変位(),
        }
    }

    /// 掃引する側のカプセルが、動く直方体に最初に触れる点を求める。刻みの始まりで既に触れている対は、
    /// 進んだ割合0で返る。
    pub fn 掃引する側のカプセルが最初に触れる点を求める(
        &self,
        掃引する側のカプセル: &形を掃引するカプセル,
    ) -> Result<動く形どうしが最初に触れる点<直方体で当たった特徴>, 動く形の対の問い合わせエラー> {
        let 還元 = 動く形の対を片側の掃引へ写す還元::二つの変位から生成する(
            掃引する側のカプセル.掃引の変位(),
            self.静止させる側の変位,
        )
        .map_err(動く形の対の問い合わせエラー::相対変位を作れない)?;
        let 片側の掃引 = 掃引する側のカプセル.掃引の変位を差し替えたカプセルを求める(還元.相対変位());
        match self
            .静止させた形への掃引の問い合わせ
            .カプセルが直方体に最初に触れる点を求める(&片側の掃引)?
        {
            カプセルが直方体に最初に触れる点::直方体に触れない => Ok(動く形どうしが最初に触れる点::二つの形は触れない),
            カプセルが直方体に最初に触れる点::直方体に触れる(接触) => {
                let 接触位置 = 還元
                    .静止させた側で得た点を接触の時刻の位置へ戻す(接触.接触位置(), 接触.動けた割合())
                    .map_err(動く形の対の問い合わせエラー::接触の時刻の位置を作れない)?;
                Ok(動く形どうしが最初に触れる点::二つの形が触れる(
                    動く形どうしの接触::生成する(接触.動けた割合(), 接触位置, 接触.接触の単位法線(), 接触.触れた特徴()),
                ))
            }
        }
    }
}
