//! 動く形の対の反証が共有する材料。動く形を組む入口と、対の問い合わせを投げる入口と、答えから接触を取り出す
//! 読み取りを持つ。
//!
//! 対の問い合わせを関数で包むのは、反証がどちらを静止させる側に選ぶかを引数の並びだけで書き分けられるように
//! するためである。対称性の反証はこの並びを入れ替えて2度呼ぶ。

use blitz_math::{クォータニオン, メートル, ローカル, 位置, 方向};

use crate::capsule::静止したカプセルで触れた特徴;
use crate::shape::{
    任意姿勢の直方体, 動く任意姿勢の直方体, 形の局所座標の位置, 形の局所座標の変位, 形を掃引するカプセル, 直方体の軸ごとの半分の長さ,
};

use super::capsule_pair_query::動くカプセルどうしの接触の問い合わせ;
use super::contact::{動く形どうしが最初に触れる点, 動く形どうしの接触};
use super::error::動く形の対の問い合わせエラー;

// 割合と位置の比較に許す幅。根が2進で割り切れない組でも、時刻から位置を組み直す誤差はこの幅に収まる。
pub(super) const 対の反証が許す幅: f64 = 1.0e-12;

pub(super) fn 局所の点(成分: [f64; 3]) -> 形の局所座標の位置 {
    match 形の局所座標の位置::生成する(成分[0], 成分[1], 成分[2]) {
        Ok(位置) => 位置,
        Err(誤り) => panic!("試験用の局所の点を作れなかった: {誤り}"),
    }
}

pub(super) fn 局所の変位(成分: [f64; 3]) -> 形の局所座標の変位 {
    match 形の局所座標の変位::生成する(成分[0], 成分[1], 成分[2]) {
        Ok(変位) => 変位,
        Err(誤り) => panic!("試験用の局所の変位を作れなかった: {誤り}"),
    }
}

pub(super) fn 動くカプセルを作る(
    軸の始点: [f64; 3], 軸の終点: [f64; 3], 半径: f64, 変位: [f64; 3]
) -> 形を掃引するカプセル {
    match 形を掃引するカプセル::生成する(局所の点(軸の始点), 局所の点(軸の終点), 半径, 局所の変位(変位)) {
        Ok(カプセル) => カプセル,
        Err(誤り) => panic!("試験用の動くカプセルを作れなかった: {誤り}"),
    }
}

pub(super) fn 動く立方体を作る(中心: [f32; 3], 半分: [f32; 3], 変位: [f64; 3]) -> 動く任意姿勢の直方体 {
    let 中心の位置 = 位置::生成する(メートル::生成する(中心[0]), メートル::生成する(中心[1]), メートル::生成する(中心[2]));
    let 半分の長さ = match 直方体の軸ごとの半分の長さ::生成する(半分.map(メートル::生成する)) {
        Ok(値) => 値,
        Err(誤り) => panic!("試験用の半分の長さを作れなかった: {誤り}"),
    };
    match 任意姿勢の直方体::生成する(中心の位置, クォータニオン::恒等(), 半分の長さ) {
        Ok(直方体) => 動く任意姿勢の直方体::生成する(直方体, 局所の変位(変位)),
        Err(誤り) => panic!("試験用の直方体を作れなかった: {誤り}"),
    }
}

pub(super) fn カプセルの対の接触を求める(
    掃引する側: &形を掃引するカプセル,
    静止させる側: &形を掃引するカプセル,
) -> Result<動く形どうしが最初に触れる点<静止したカプセルで触れた特徴>, 動く形の対の問い合わせエラー> {
    動くカプセルどうしの接触の問い合わせ::静止させる側のカプセルから生成する(静止させる側)
        .掃引する側のカプセルが最初に触れる点を求める(掃引する側)
}

pub(super) fn カプセルの対の接触を確かめて求める(
    掃引する側: &形を掃引するカプセル,
    静止させる側: &形を掃引するカプセル,
) -> 動く形どうしが最初に触れる点<静止したカプセルで触れた特徴> {
    match カプセルの対の接触を求める(掃引する側, 静止させる側) {
        Ok(答え) => 答え,
        Err(誤り) => panic!("動くカプセルどうしの問い合わせが失敗した: {誤り}"),
    }
}

pub(super) fn 接触を取り出す<触れた特徴>(
    答え: 動く形どうしが最初に触れる点<触れた特徴>
) -> 動く形どうしの接触<触れた特徴> {
    match 答え {
        動く形どうしが最初に触れる点::二つの形が触れる(接触) => 接触,
        動く形どうしが最初に触れる点::二つの形は触れない => panic!("触れるはずの形が触れなかった"),
    }
}

pub(super) fn 位置の成分(位置: 形の局所座標の位置) -> [f64; 3] {
    [位置.xのメートル(), 位置.yのメートル(), 位置.zのメートル()]
}

pub(super) fn 方向の成分(方向: 方向<ローカル>) -> [f32; 3] {
    [方向.x(), 方向.y(), 方向.z()]
}

pub(super) fn 三成分が近いことを確かめる(実測: [f64; 3], 期待: [f64; 3], 何の値か: &str) {
    for 軸 in 0usize..3 {
        assert!(
            (実測[軸] - 期待[軸]).abs() <= 対の反証が許す幅,
            "{何の値か}の軸{軸}が期待から離れている(実測{}、期待{})",
            実測[軸],
            期待[軸]
        );
    }
}
