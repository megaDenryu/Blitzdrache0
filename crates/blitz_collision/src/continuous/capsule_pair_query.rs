//! 動くカプセルどうしの接触の問い合わせ: 平行移動する2つのカプセルが最初に触れる時刻と場所を求める操作サービス。
//! 対の一方を静止させる側としてコンストラクタで受け取り、その形から片側の掃引の問い合わせを組んで保持する。
//!
//! 新しい幾何の数学をここに書かない。担当は、還元で相対変位を作り、掃引の変位を差し替えたカプセルを静止させた
//! 相手へ投げ、返った接触の位置を実際に触れた瞬間へ戻すことだけである。時刻を解くのは静止したカプセルへの掃引である。
//!
//! 静止させる側の形は刻みの始まりの姿勢で取る。相手に与える相対変位が、対の2つの動きの差をすべて引き受けるためである。

use crate::capsule::{
    カプセルが静止したカプセルに最初に触れる点, 静止したカプセルで触れた特徴, 静止したカプセルへのカプセルの掃引の問い合わせ
};
use crate::shape::{形の局所座標の変位, 形を掃引するカプセル};

use super::contact::{動く形どうしが最初に触れる点, 動く形どうしの接触};
use super::error::動く形の対の問い合わせエラー;
use super::reduction::動く形の対を片側の掃引へ写す還元;

/// 動くカプセルどうしの接触の問い合わせ。静止させる側のカプセルとその変位を保持する操作サービスである。
pub struct 動くカプセルどうしの接触の問い合わせ {
    静止させた形への掃引の問い合わせ: 静止したカプセルへのカプセルの掃引の問い合わせ,
    静止させる側の変位: 形の局所座標の変位,
}

impl 動くカプセルどうしの接触の問い合わせ {
    /// 対の一方を静止させる側として受け取り、その形の掃引の問い合わせと変位を保持する。
    pub fn 静止させる側のカプセルから生成する(静止させる側のカプセル: &形を掃引するカプセル) -> Self {
        Self {
            静止させた形への掃引の問い合わせ:
                静止したカプセルへのカプセルの掃引の問い合わせ::静止したカプセルから生成する(
                    静止させる側のカプセル.動きを取り去ったカプセルを求める(),
                ),
            静止させる側の変位: 静止させる側のカプセル.掃引の変位(),
        }
    }

    /// 掃引する側のカプセルが、静止させる側のカプセルに最初に触れる点を求める。刻みの始まりで既に触れている
    /// 対は、進んだ割合0で返る。
    pub fn 掃引する側のカプセルが最初に触れる点を求める(
        &self,
        掃引する側のカプセル: &形を掃引するカプセル,
    ) -> Result<動く形どうしが最初に触れる点<静止したカプセルで触れた特徴>, 動く形の対の問い合わせエラー> {
        let 還元 = 動く形の対を片側の掃引へ写す還元::二つの変位から生成する(
            掃引する側のカプセル.掃引の変位(),
            self.静止させる側の変位,
        )
        .map_err(動く形の対の問い合わせエラー::相対変位を作れない)?;
        let 片側の掃引 = 掃引する側のカプセル.掃引の変位を差し替えたカプセルを求める(還元.相対変位());
        match self
            .静止させた形への掃引の問い合わせ
            .カプセルが静止したカプセルに最初に触れる点を求める(&片側の掃引)?
        {
            カプセルが静止したカプセルに最初に触れる点::静止したカプセルに触れない => {
                Ok(動く形どうしが最初に触れる点::二つの形は触れない)
            }
            カプセルが静止したカプセルに最初に触れる点::静止したカプセルに触れる(接触) => {
                let 接触位置 = 還元
                    .静止させた側で得た点を接触の時刻の位置へ戻す(接触.接触位置(), 接触.動けた割合())
                    .map_err(動く形の対の問い合わせエラー::接触の時刻の位置を作れない)?;
                Ok(動く形どうしが最初に触れる点::二つの形が触れる(
                    動く形どうしの接触::生成する(接触.動けた割合(), 接触位置, 接触.接触の単位法線(), 接触.触れた特徴()),
                ))
            }
        }
    }
}
