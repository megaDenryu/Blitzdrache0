//! 動く形どうしが最初に触れた点と、触れなかったことを表す枝。
//!
//! 相手の形の種類ごとに写した型を置かないのは、答えの4つの値のうち3つ(進んだ割合・接触位置・接触の単位法線)が
//! どの組でも同じ意味と同じ型であり、違うのは触れた特徴の型だけだからである。特徴を型の引数で受けることで、
//! 動くカプセルどうしの答えと動くカプセルと動く直方体の答えを1つの型が持てる。
//!
//! 接触位置は、実際に触れた瞬間の位置である。片側の掃引が返すのは静止させた側の刻みの始まりの姿勢の上の点で
//! あるため、還元がその点を接触の時刻まで進めたものをここへ入れる。
//!
//! 触れた特徴が指すのは静止させた側の形の部分である。対のどちらを静止させる側に選ぶかで、返る特徴も
//! 単位法線の符号も変わる。時刻と位置は選び方に依らない。

use blitz_math::{ローカル, 方向};

use crate::shape::形の局所座標の位置;
use crate::solver::掃引で動けた割合;

/// 動く形どうしが最初に触れる点。刻みの全体を動いても触れなかった枝と、触れた接触を持つ枝の2つである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 動く形どうしが最初に触れる点<触れた特徴> {
    /// 2つの形は、それぞれの変位の全体を動いても触れなかった。
    二つの形は触れない,
    /// 刻みの途中で2つの形が触れ、その最初の接触を持つ。
    二つの形が触れる(動く形どうしの接触<触れた特徴>),
}

/// 動く形どうしが触れた1つの事実。進んだ割合・接触位置・接触の単位法線・静止させた側で触れた特徴を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 動く形どうしの接触<触れた特徴> {
    触れるまでに進んだ割合: 掃引で動けた割合,
    接触位置: 形の局所座標の位置,
    接触の単位法線: 方向<ローカル>,
    静止させた側で触れた特徴: 触れた特徴,
}

impl<触れた特徴> 動く形どうしの接触<触れた特徴> {
    pub(super) fn 生成する(
        触れるまでに進んだ割合: 掃引で動けた割合,
        接触位置: 形の局所座標の位置,
        接触の単位法線: 方向<ローカル>,
        静止させた側で触れた特徴: 触れた特徴,
    ) -> Self {
        Self {
            触れるまでに進んだ割合,
            接触位置,
            接触の単位法線,
            静止させた側で触れた特徴,
        }
    }

    /// 1つの刻みのうち、2つの形が触れるまでに進んだ分の割合。どちらの形もこの割合だけ自分の変位を進んでいる。
    /// 刻みの始まりで既に触れていた場合は0である。
    pub fn 触れるまでに進んだ割合(&self) -> 掃引で動けた割合 {
        self.触れるまでに進んだ割合
    }

    /// 触れた瞬間の接触点。静止させた側の表面の上の点であり、その時刻の掃引した側の表面もこの点を通る。
    pub fn 接触位置(&self) -> 形の局所座標の位置 {
        self.接触位置
    }

    /// 静止させた側の表面から、掃引した側の軸へ向かう単位方向。
    pub fn 接触の単位法線(&self) -> 方向<ローカル> {
        self.接触の単位法線
    }

    /// 静止させた側の形のどの部分に触れたか。
    pub fn 静止させた側で触れた特徴(&self) -> &触れた特徴 {
        &self.静止させた側で触れた特徴
    }
}
