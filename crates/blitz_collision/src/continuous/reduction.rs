//! 動く形の対を片側の掃引へ写す還元: 2つの平行移動する形の対を、片方を静止させて相手に2つの変位の差を与えた
//! 片側の掃引へ写す。写した掃引の答える時刻は、元の問いの初回接触時刻と数学的に厳密に同じである。
//!
//! 等価の根拠。割合tの時点で一方はtかけるa、他方はtかけるbだけ進んでおり、2つの形の相対的な位置関係は
//! tかける(a - b)だけ動いた片側の掃引と同じである。したがって「触れている」が成り立つtの集合が2つの問いで
//! 一致し、その最小値も一致する。この等価は平行移動だからこそ成り立つ。回転が入ると2つの動きの差が1つの
//! 平行移動にならず、この還元は使えない。
//!
//! 静止させる側の変位を保持するのは、写した掃引が返す接触の位置が静止させた側の刻みの始まりの姿勢の上の点で
//! あり、実際に触れた瞬間の位置がそこから静止させる側の変位を割合の分だけ進めた点だからである。接触の単位法線と
//! 時刻は平行移動で変わらないため戻さない。
//!
//! 誤差。この還元が持ち込む丸めは成分ごとの減算1回だけであり、相対変位の相対誤差は倍精度の丸めの単位以下である。
//! これが接触の時刻へ伝わる量は、隔たりが時刻について変化する速さで割ったものになる。正面から近づく2つの形では
//! 時刻の相対誤差も丸めの単位と同じ程度である。かすめる接触では隔たりの変化が遅く、その割り算が誤差を拡大する。
//! 掃引の2次方程式の根が持つ誤差と同じ性質であるため、ここでも厳密な上界は導かない
//! (`crates/blitz_collision/src/solver/quadratic.rs`)。
//!
//! 非正規化数。相対変位が非正規化数へ落ちるほど小さい対では、写した掃引の途中で新たに触れることが起こらない。
//! その対がほとんど動かないためであり、触れているかどうかは掃引の始まりの隔たりが決める。その判定が比べる
//! 目標値である半径の和の二乗は、カプセルの半径が下限2のマイナス24乗メートルを守ることで常に正規化数に
//! 収まるため、目標値が0へ潰れて触れていない対を触れていると偽ることはない
//! (`crates/blitz_collision/src/shape/capsule_radius_lower_limit.rs`)。
//!
//! 接触の時刻がわずかに遅れると、そのぶん2つの形が食い込む。食い込んだ状態は次の刻みで拾い直される。次の刻みの
//! 始まりで隔たりが既に触れている範囲にあり、掃引の始まりから触れているものとして割合0と最も近い特徴の法線が
//! 返るからである。したがって遅れは薄い形をすり抜ける貫通にはならない。
//!
//! 相対変位に形の座標と同じ上限を課し直すのは、掃引の2次方程式の係数と判別式が桁あふれしないという算術が
//! その上限を前提にしているためである。上限に収まる2つの変位の差はその2倍まで育ちうるので、差を作った後に
//! もう一度検査を通す。

use crate::shape::{形の局所座標の位置, 形の局所座標の変位, 形の局所座標の生成エラー};
use crate::solver::掃引で動けた割合;

/// 動く形の対を、片方を静止させた片側の掃引へ写す還元。静止させる側の変位と、掃引する側へ与える相対変位を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 動く形の対を片側の掃引へ写す還元 {
    静止させる側の変位: 形の局所座標の変位,
    相対変位: 形の局所座標の変位,
}

impl 動く形の対を片側の掃引へ写す還元 {
    /// 2つの変位の差を相対変位として作る。差が形の座標の絶対値の上限を越えたら型付きエラーで拒む。
    pub fn 二つの変位から生成する(
        掃引する側の変位: 形の局所座標の変位,
        静止させる側の変位: 形の局所座標の変位,
    ) -> Result<Self, 形の局所座標の生成エラー> {
        let 相対変位 = 形の局所座標の変位::生成する(
            掃引する側の変位.xのメートル() - 静止させる側の変位.xのメートル(),
            掃引する側の変位.yのメートル() - 静止させる側の変位.yのメートル(),
            掃引する側の変位.zのメートル() - 静止させる側の変位.zのメートル(),
        )?;
        Ok(Self {
            静止させる側の変位,
            相対変位,
        })
    }

    /// 相手を静止させたときに、掃引する側へ与える変位。2つの変位の差である。
    pub fn 相対変位(&self) -> 形の局所座標の変位 {
        self.相対変位
    }

    /// 静止させた側の刻みの始まりの姿勢の上で得た点を、実際に触れた瞬間の位置へ戻す。静止させる側の変位を
    /// 割合の分だけ進める。
    pub fn 静止させた側で得た点を接触の時刻の位置へ戻す(
        &self,
        点: 形の局所座標の位置,
        触れるまでに進んだ割合: 掃引で動けた割合,
    ) -> Result<形の局所座標の位置, 形の局所座標の生成エラー> {
        点.変位だけ進んだ位置を求める(self.静止させる側の変位.実数倍する(触れるまでに進んだ割合.値()))
    }
}
