//! 接触は面へ向かう掃引だけが持つ: 掃引の変位と、接触位置から軸へ向かう向きの内積が負である候補だけを
//! 接触として数える規則である。始まりから触れている候補(隔たりが半径以下)と、掃引の途中の根の両方に
//! 同じ判定を通す。高さ場の三角形・任意姿勢の直方体・一般の三角形の3経路が、この1つの型で判定する。
//!
//! 規則が要るのは、面に隙間なく触れたまま面に沿う掃引が一歩も動けなかったためである。始まりで半径以内に
//! 居る候補を向きを問わず割合0で返すと、面に沿う変位も面から離れる変位も止まり、食い込みから抜け出せない。
//! 掃引の途中の根も同じ判定を通すのは、始まりの候補を捨てた直後に、同じ特徴から離れる側の根(隔たりが
//! 半径を越えて広がる時刻)が割合0付近で見つかり、結局止まるためである。離れる側の根とかすめる根は
//! 最初に触れる時刻ではない。最初に触れる瞬間は隔たりが縮んでいる瞬間であり、その候補は必ず面へ向かう。
//!
//! 平行の幅。面に沿わせた変位は呼び出し側の丸めで法線の成分をわずかに持ち、内積の符号が丸めで決まる。
//! 符号だけで判定すると、同じ位置から同じ面に沿う掃引が丸めの向きで動けたり止まったりする。そのため
//! 内積の絶対値が2つの長さの積の2の20乗分の1に満たない候補は平行として捨てる。単精度の刻み(2の24乗分の1)
//! を16倍で覆う幅であり、この角で1メートル動いた食い込みは1マイクロメートルに満たない。
//!
//! 零の変位は動きを持たないため、この判定は候補をすべて接触として持つ。零の変位の掃引は「今触れているか」
//! の問いとして働く。

use super::displacement::求解が扱う変位;

// 内積の絶対値が2つの長さの積に対してこの比に満たない候補を、平行として捨てる。2の20乗分の1である。
const 平行とみなす余弦の幅: f64 = 1.0 / 1_048_576.0;

pub(crate) struct 掃引が面へ向かうかの判定<変位> {
    掃引の変位: 変位,
    変位の長さの二乗: f64,
}

impl<変位: 求解が扱う変位> 掃引が面へ向かうかの判定<変位> {
    pub(crate) fn 掃引の変位から生成する(掃引の変位: 変位) -> Self {
        Self {
            掃引の変位,
            変位の長さの二乗: 掃引の変位.長さの二乗(),
        }
    }

    // 接触位置から軸へ向かう向きの候補を、接触として持つか。向きの長さは問わない(単位向きでも半径の長さでもよい)。
    pub(crate) fn 接触として持つか(&self, 接触位置から軸へ向かう変位: 変位) -> bool {
        if self.変位の長さの二乗 <= 0.0 {
            return true;
        }
        let 内積 = self.掃引の変位.内積(接触位置から軸へ向かう変位);
        if 内積 >= 0.0 {
            return false;
        }
        let 長さの積の二乗 = self.変位の長さの二乗 * 接触位置から軸へ向かう変位.長さの二乗();
        内積 * 内積 > 平行とみなす余弦の幅 * 平行とみなす余弦の幅 * 長さの積の二乗
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::shape::形の局所座標の変位;

    fn 変位(x: f64, y: f64, z: f64) -> 形の局所座標の変位 {
        match 形の局所座標の変位::生成する(x, y, z) {
            Ok(変位) => 変位,
            Err(誤り) => panic!("試験用の変位を作れなかった: {誤り}"),
        }
    }

    #[test]
    fn 面へ向かう変位だけを接触として持つ() {
        let 判定 = 掃引が面へ向かうかの判定::掃引の変位から生成する(変位(1.0, -1.0, 0.0));
        assert!(判定.接触として持つか(変位(0.0, 0.5, 0.0)));
        assert!(!判定.接触として持つか(変位(0.0, -0.5, 0.0)));
        assert!(!判定.接触として持つか(変位(1.0, 1.0, 0.0)));
    }

    #[test]
    fn 丸めの幅の中の傾きは平行として捨てる() {
        let 判定 = 掃引が面へ向かうかの判定::掃引の変位から生成する(変位(1.0, -1.0e-7, 0.0));
        assert!(!判定.接触として持つか(変位(0.0, 1.0, 0.0)));
        let 判定 = 掃引が面へ向かうかの判定::掃引の変位から生成する(変位(1.0, -1.0e-5, 0.0));
        assert!(判定.接触として持つか(変位(0.0, 1.0, 0.0)));
    }

    #[test]
    fn 零の変位はどの候補も接触として持つ() {
        let 判定 = 掃引が面へ向かうかの判定::掃引の変位から生成する(変位(0.0, 0.0, 0.0));
        assert!(判定.接触として持つか(変位(0.0, -1.0, 0.0)));
    }
}
