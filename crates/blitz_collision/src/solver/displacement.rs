//! 求解が扱う変位の能力。内積・外積・実数倍・加減と長さの二乗だけを数え上げる。
//!
//! 能力で受けるのは、高さ場の格子原点を基準にした変位と、形の局所座標を基準にした変位の2つが同じ式を
//! 使うためである。2つを1つの型にまとめないのは、成分の意味(東・天頂・南と、局所座標のx・y・z)も、
//! 成分の絶対値へ課す上限の根拠も別だからである。
//!
//! 有限性をここで検査し直さないのは、上限を課すのが実装する型の側の役目であり、上限から係数と判別式が
//! 倍精度の範囲を出ないことをそれぞれの型が算術で示しているためである。

pub(crate) trait 求解が扱う変位: Copy {
    fn 内積(self, 相手: Self) -> f64;
    fn 外積(self, 相手: Self) -> Self;
    fn 長さの二乗(self) -> f64;
}
