//! 軸の端: カプセルの軸の2つの端のどちらかである。カプセルの両端は半球であり、その半球が形へ触れる
//! 接触は、軸の端に置いた球の接触と同じものになる。掃引の求解が球として扱う部分を名前で指すために置く。
//!
//! 公開するのは、静止したカプセルへの掃引が「軸のどちらの端の半球に触れたか」を答えとして返すためである。
//! 数え上げの並びと並びの位置は求解の内側の決まりであるからクレートの中に閉じたままである。

/// カプセルの軸の2つの端のどちらか。軸の上の比を0から1へ測る向きが、この2つの名前と対応する。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 軸の端 {
    /// 軸の上の比が0の側。
    始点の側,
    /// 軸の上の比が1の側。
    終点の側,
}

impl 軸の端 {
    // 2つの端を、求解が候補を数える順に並べる。
    pub(crate) fn 並べる() -> [Self; 2] {
        [Self::始点の側, Self::終点の側]
    }

    // 掃引するカプセルが軸の端点を並べた組の中の位置。
    pub(crate) fn 並びの位置(self) -> usize {
        match self {
            Self::始点の側 => 0,
            Self::終点の側 => 1,
        }
    }
}
