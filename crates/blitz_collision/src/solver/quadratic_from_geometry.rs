//! 特徴の幾何から掃引の2次方程式を組む局面。呼ばれるのは候補1件につき1回、根を解く手前である。
//! 触れるのは渡された変位と半径だけであり、方程式が持つ3つの係数を組んで返す以外のことはしない。
//!
//! 方程式の定義と根の求め方(`quadratic.rs`)と別の局面に置くのは、係数を組む側が形ごとの幾何を知っているのに
//! 対し、根を解く側は係数しか知らないためである。形が増えるとここへ組み方が増え、解き方は増えない。
//!
//! 4つの組み方で、高さ場の三角形と任意姿勢の直方体の両方の候補をすべて賄う。平面と球は面と軸の端の組、
//! 点と球は頂点と軸の端の組、直線と球は辺と軸の端の組および頂点と軸の内側の組、2つの直線は辺と軸の内側の組で
//! 使う。同じ式を形ごとに書き写すと、片方だけを直した食い違いが答えの違いとして出るまで見つからない。

use super::displacement::求解が扱う変位;
use super::quadratic::掃引の2次方程式;

impl 掃引の2次方程式 {
    // 平面と球の隔たりが半径に等しくなる時刻。隔たりは時刻の1次式であるから、2乗した形が2次方程式になる。
    // 2乗した形で解くのは、球が平面のどちら側から来ても同じ1つの式で扱うためである。
    pub(crate) fn 平面と球の隔たりから組む(始まりの隔たり: f64, 隔たりの速度: f64, 半径の二乗: f64) -> Self {
        Self::生成する(
            隔たりの速度 * 隔たりの速度,
            2.0 * 始まりの隔たり * 隔たりの速度,
            始まりの隔たり * 始まりの隔たり - 半径の二乗,
        )
    }

    // 固定の点と球の隔たりが半径に等しくなる時刻。始まりの変位は、その点から掃引の始まりの球の中心へ向かう。
    pub(crate) fn 点と球の隔たりから組む<変位: 求解が扱う変位>(
        始まりの変位: 変位, 掃引の変位: 変位, 半径の二乗: f64
    ) -> Self {
        Self::生成する(
            掃引の変位.長さの二乗(),
            2.0 * 始まりの変位.内積(掃引の変位),
            始まりの変位.長さの二乗() - 半径の二乗,
        )
    }

    // 直線と球の隔たりが半径に等しくなる時刻。隔たりの二乗は、直線の1点から球の中心への変位と直線の変位の
    // 外積の長さの二乗を、直線の長さの二乗で割ったものであるから、分母を払うと2次方程式になる。
    // 始まりの変位は、直線の上の基準の点から掃引の始まりの球の中心へ向かう。
    pub(crate) fn 直線と球の隔たりから組む<変位: 求解が扱う変位>(
        始まりの変位: 変位,
        掃引の変位: 変位,
        直線の変位: 変位,
        直線の長さの二乗: f64,
        半径の二乗: f64,
    ) -> Self {
        let 始まりの外積 = 始まりの変位.外積(直線の変位);
        let 速度の外積 = 掃引の変位.外積(直線の変位);
        Self::生成する(
            速度の外積.長さの二乗(),
            2.0 * 速度の外積.内積(始まりの外積),
            始まりの外積.長さの二乗() - 半径の二乗 * 直線の長さの二乗,
        )
    }

    // ねじれの位置にある2つの直線の隔たりが半径に等しくなる時刻。隔たりは両方に垂直な向き(2つの変位の外積)へ
    // 射影した長さであり、射影は時刻の1次式であるから平面と球と同じ形へ帰着する。2つの直線が平行なとき外積は
    // 零になり隔たりが定まらないため`None`を返す。平行な場合の最も早い接触は、どちらかの直線の端の候補が答える。
    pub(crate) fn 二つの直線の隔たりから組む<変位: 求解が扱う変位>(
        始まりの変位: 変位,
        掃引の変位: 変位,
        第1の直線の変位: 変位,
        第2の直線の変位: 変位,
        半径の二乗: f64,
    ) -> Option<Self> {
        let 両方に垂直な向き = 第1の直線の変位.外積(第2の直線の変位);
        let 向きの長さの二乗 = 両方に垂直な向き.長さの二乗();
        if 向きの長さの二乗 <= 0.0 {
            return None;
        }
        Some(Self::平面と球の隔たりから組む(
            始まりの変位.内積(両方に垂直な向き),
            掃引の変位.内積(両方に垂直な向き),
            半径の二乗 * 向きの長さの二乗,
        ))
    }
}
