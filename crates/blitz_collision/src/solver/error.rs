//! 求解が扱う無次元の媒介変数を作るときに破れる条件。
//!
//! 線分の媒介変数と掃引で動けた割合はどちらも0以上1以下の無次元量であり、破れる条件も1つで同じである。
//! 形ごとの問い合わせの失敗の語彙は、この型を`#[from]`で畳み込む。形ごとに同じ枝を書くと、
//! 同じ破れが形の数だけ別の綴りで現れる。

use thiserror::Error;

/// 求解が扱う無次元の媒介変数を作るときに破れる条件。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 無次元の媒介変数の生成エラー {
    /// 媒介変数が0以上1以下の有限値でなかった。
    #[error("求解の媒介変数が0以上1以下の有限値でない")]
    媒介変数が0以上1以下の有限値でない,
}
