//! 掃引で動けた割合: 掃引の変位のうち、形に触れるまでに動けた分の割合である。0以上1以下の無次元量であり、
//! 0は動く前から既に触れていたこと、1は変位の全体を動けたことを表す。
//!
//! 裸の実数で運ばないのは、この量が長さでも高さでも升目の中の比でも線分の媒介変数でもない別の量であり、
//! 実数のままではそれらと取り違えても型が通るためである。
//!
//! 2次方程式の根を割合として受け入れるかどうかの判定もこの型が持つ。判定を求解の側の区間の検査に置くと、
//! 端をわずかに越えた根がそこで捨てられ、端へ寄せる経路へ届かない。受理と寄せは同じ1つの入口でなければならない。
//!
//! 寄せられる幅の選び方。根のずれは、判別式を組む減算の桁落ちの比に倍精度の丸めの単位を掛けた程度である。
//! 掃引の終わりでちょうど触れる入力(半径2.0925440266566975・始まりの隔たり330.993339491018・
//! 法線方向の変位-328.9007954643613)では桁落ちの比が2.5かける10の4乗であり、根は1を1.24かける10のマイナス14乗
//! だけ越える。幅を2の32乗分の1へ置くと、比が10の9乗まで育っても受理する。これは導いた上界ではなく選んだ幅で
//! あり、これを越えた根は接触ではないものとして捨てる。広く受理する代償は、掃引の端でしか起きない接触を端の
//! 正準値で答えることであり、位置のずれは幅と掃引の変位の積(1メートルの掃引で0.2ナノメートル)に収まる。
//! 捨てる側の代償は接触を丸ごと取り逃すことであり、こちらのほうが重い。

use super::error::無次元の媒介変数の生成エラー;

// 2次方程式の根を0以上1以下の端へ寄せて受理できる幅。2の32乗分の1である。
const 根を端へ寄せられる幅: f64 = 1.0 / 4_294_967_296.0;

/// 掃引の変位のうち、形に触れるまでに動けた分の割合。0以上1以下の無次元量である。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 掃引で動けた割合(f64);

impl 掃引で動けた割合 {
    /// 0以上1以下の有限値だけを受け付ける。範囲の外は型付きエラーで拒む。
    pub fn 生成する(値: f64) -> Result<Self, 無次元の媒介変数の生成エラー> {
        if !値.is_finite() || !(0.0..=1.0).contains(&値) {
            return Err(無次元の媒介変数の生成エラー::媒介変数が0以上1以下の有限値でない);
        }
        Ok(Self(値))
    }

    // 2次方程式の根を割合として受理する。0以上1以下から寄せられる幅だけ外れた根は端の正準値へ寄せて受理し、
    // それより外れた根は掃引の中で起きる接触ではないため`None`を返す。
    pub(crate) fn 根を端へ寄せて受理する(根: f64) -> Option<Self> {
        if !根.is_finite() || !(-根を端へ寄せられる幅..=1.0 + 根を端へ寄せられる幅).contains(&根) {
            return None;
        }
        Some(Self(根.clamp(0.0, 1.0)))
    }

    // 動く前から既に触れていた場合の割合。
    pub(crate) fn 一歩も動けなかった() -> Self {
        Self(0.0)
    }

    /// 割合そのもの。0は動く前から触れていたこと、1は変位の全体を動けたことを表す。
    pub fn 値(&self) -> f64 {
        self.0
    }
}
