//! 量の小さい候補だけを覚える器。特徴を辿る求解と、升目や形を辿る走査の両方が使う。
//! 候補の一覧をヒープへ貯めずに、渡されたそばから捨てるためである。
//!
//! 比べる量を値と別に受け取るのは、同じ器が2つの量で使われるためである。求解の中では特徴に触れ始める時刻を、
//! 走査の中では掃引の始まりの隔たりの二乗と接触の時刻を比べる。量を値から取り出す決まりを器が持つと、
//! どちらの量で比べるのかが器の側の約束になり、用途ごとに器が増える。
//!
//! 等しい量の候補が並んだときは先に渡されたものを残す。覆いの升目の並びと形の並びと特徴の並びが
//! すべて固定であるから、これで答えが入力だけで決まる。隣り合う升目や2つの三角形が共有する辺と頂点は
//! 同じ接触を複数回返すが、どれを残しても位置と法線は同じ点を指す。

pub(crate) struct 最も小さい量の候補だけを覚える器<値> {
    現在の最小: Option<値>,
    現在の量: f64,
}

impl<値> 最も小さい量の候補だけを覚える器<値> {
    pub(crate) fn まだ何も無い状態から始める() -> Self {
        Self {
            現在の最小: None,
            現在の量: f64::INFINITY,
        }
    }

    pub(crate) fn 候補を1つ数える(&mut self, 量: f64, 値: 値) {
        if self.現在の最小.is_none() || 量 < self.現在の量 {
            self.現在の最小 = Some(値);
            self.現在の量 = 量;
        }
    }

    // 今のところ最小である候補。取り出さずに読む入口を別に持つのは、走査の側が候補を数えながら現在の最小を
    // 読み、そこまでで覆いを縮めるためである。取り出す側は器を使い切るため、途中では使えない。
    pub(crate) fn 覚えている候補を見る(&self) -> Option<&値> {
        self.現在の最小.as_ref()
    }

    pub(crate) fn 覚えている候補を取り出す(self) -> Option<値> {
        self.現在の最小
    }
}
