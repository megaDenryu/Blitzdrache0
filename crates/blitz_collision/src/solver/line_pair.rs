//! 二つの直線の最近接の媒介変数: ねじれの位置にある2つの直線が最も近づく点を、それぞれの直線の上の比で
//! 表したものである。どちらの比も、その直線の始点を0・終点を1として測る。
//!
//! 2つの比を裸の実数の対で持ち回すと、どちらがどちらの直線の比かを署名が語らなくなるためこの型で包む。
//! 求め方は、隔たりの二乗を2つの比の2次式とみて偏微分を0に置いた連立1次方程式であり、その行列式は
//! 2つの変位の外積の長さの二乗である。平行な2直線では0になり、最近接点が1組に定まらない。

use super::displacement::求解が扱う変位;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 二つの直線の最近接の媒介変数 {
    第1の直線の比: f64,
    第2の直線の比: f64,
}

impl 二つの直線の最近接の媒介変数 {
    // 2つの比を求め、どちらもそれぞれの範囲(0以上1以下)に収まる場合だけ返す。平行な2直線と、
    // 長さ0の変位では最近接点が定まらないため`None`を返す。
    pub(crate) fn 両方の範囲に収まる組を求める<変位: 求解が扱う変位>(
        第1の直線の変位: 変位,
        第2の直線の変位: 変位,
        第2の始点から第1の始点への変位: 変位,
    ) -> Option<Self> {
        let 行列式 = 第1の直線の変位.外積(第2の直線の変位).長さの二乗();
        if 行列式 <= 0.0 {
            return None;
        }
        let 第1の長さの二乗 = 第1の直線の変位.長さの二乗();
        let 第2の長さの二乗 = 第2の直線の変位.長さの二乗();
        let 二つの変位の内積 = 第1の直線の変位.内積(第2の直線の変位);
        let 第1への射影 = 第2の始点から第1の始点への変位.内積(第1の直線の変位);
        let 第2への射影 = 第2の始点から第1の始点への変位.内積(第2の直線の変位);
        let 第1の直線の比 = (二つの変位の内積 * 第2への射影 - 第2の長さの二乗 * 第1への射影) / 行列式;
        let 第2の直線の比 = (第1の長さの二乗 * 第2への射影 - 二つの変位の内積 * 第1への射影) / 行列式;
        if !(0.0..=1.0).contains(&第1の直線の比) || !(0.0..=1.0).contains(&第2の直線の比) {
            return None;
        }
        Some(Self {
            第1の直線の比,
            第2の直線の比,
        })
    }

    pub(crate) fn 第1の直線の比(&self) -> f64 {
        self.第1の直線の比
    }

    pub(crate) fn 第2の直線の比(&self) -> f64 {
        self.第2の直線の比
    }
}
