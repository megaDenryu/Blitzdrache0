//! 線分の媒介変数: 線分の始点を0、終点を1とした0以上1以下の無次元量である。
//!
//! 裸の実数で運ばないのは、この量が長さでも高さでも升目の中の比でもない別の量であり、
//! 実数のままではそれらと取り違えても型が通るためである。
//!
//! 形の種類に依らない量であるため、高さ場の三角形への当たりと任意姿勢の直方体への当たりが同じ型で答える。

use super::error::無次元の媒介変数の生成エラー;

/// 線分の始点を0、終点を1とした0以上1以下の無次元量。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 線分の媒介変数(f64);

impl 線分の媒介変数 {
    /// 0以上1以下の有限値だけを受け付ける。範囲の外は型付きエラーで拒む。
    pub fn 生成する(値: f64) -> Result<Self, 無次元の媒介変数の生成エラー> {
        if !値.is_finite() || !(0.0..=1.0).contains(&値) {
            return Err(無次元の媒介変数の生成エラー::媒介変数が0以上1以下の有限値でない);
        }
        Ok(Self(値))
    }

    // 0以上1以下からわずかに外れた値を端へ寄せて作る。走査は升目の境界へ達する時刻を割り算で求めるため、
    // 線分の終わりちょうどで当たった媒介変数が1をほんの少し越えることがある。非有限の値は寄せずに型付きエラーで拒む。
    pub(crate) fn 端へ寄せて生成する(値: f64) -> Result<Self, 無次元の媒介変数の生成エラー> {
        if !値.is_finite() {
            return Err(無次元の媒介変数の生成エラー::媒介変数が0以上1以下の有限値でない);
        }
        Ok(Self(値.clamp(0.0, 1.0)))
    }

    /// 媒介変数そのもの。
    pub fn 値(&self) -> f64 {
        self.0
    }
}
