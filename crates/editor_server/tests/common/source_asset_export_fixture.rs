//! `source_asset_export_*`試験が共有する、小さな区画割りと大域世界の組み立てヘルパー。
#![allow(clippy::unwrap_used)]

use editor_server::{
    ファイル保管庫, プロジェクト保管庫, マザーハイトマップ, 世界の区画割り, 位置3次元, 大域世界構造, 広域道路
};

pub fn 小さな区画割り() -> 世界の区画割り {
    世界の区画割り {
        一辺のメートル: 8.0,
        軸あたりチャンク数: 2,
        チャンクあたり格子解像度: 2,
    }
}

pub fn 大域世界を保存する(保管庫: &ファイル保管庫, 区画割り: 世界の区画割り) {
    let 構造 = 大域世界構造 {
        区画割り,
        広域道路一覧: vec![広域道路 {
            制御点列: vec![位置3次元 { x: 0.0, y: 0.0, z: 0.0 }],
            全幅メートル: 4.0,
            細分割数: 4,
        }],
    };
    保管庫.大域世界の構造を検証して保存する(構造).unwrap();
}

/// マザーハイトマップを`高さ(x,z) = z*一辺頂点数 + x`という、位置ごとに一意な値で埋める。
/// 隣接チャンクの境界一致は「たまたま同じ定数」でなく「同じ添字を指した」ことで検査したいため、一意な値にする。
pub fn マザーを一意な値で保存する(保管庫: &ファイル保管庫, 区画割り: 世界の区画割り) {
    let 一辺頂点数 = 区画割り.マザーハイトマップの格子解像度().unwrap();
    let mut バイト列 = Vec::new();
    for z in 0..一辺頂点数 {
        for x in 0..一辺頂点数 {
            let 収まる値 = u16::try_from(z * 一辺頂点数 + x).unwrap();
            バイト列.extend_from_slice(&f32::from(収まる値).to_le_bytes());
        }
    }
    let 格子 = マザーハイトマップ::生成する(一辺頂点数, バイト列).unwrap();
    保管庫.大域世界の高さ格子を検証して保存する(格子).unwrap();
}
