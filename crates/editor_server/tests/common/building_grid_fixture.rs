//! 建物の格子の試験の材料。道具が新しい建物を作った直後の格子のJSONと、そこから升目を空にした格子を持つ。
//!
//! JSONを直に書くのは、この試験が確かめるのが「ブラウザが送る綴りのままサーバーが受け取れるか」だからである。
//! 型契約の値から直列化すると、欄の名前の食い違いを型が先に吸収してしまう。

use std::path::Path;

use editor_server::{チャンク構造, 位置3次元, 建物の配置, 散布の設定};
use serde_json::{Value, json};

pub const 試験の建物定義の識別子: &str = "grid_house_one_bay";

/// 外部アセットの置き場があるか。部品の実体を1つも読まずに決まる検査と、読む必要のある検査を分けるために使う。
pub fn 外部アセットの置き場があるか() -> bool {
    let 台帳 = blitz_asset_compiler::建物の格子の台帳::空から始める();
    let 組み立て係 = blitz_asset_compiler::建物外形カタログの組み立て係::台帳を持たせて生成する(台帳);
    !matches!(
        組み立て係.組み立てる(),
        Err(blitz_asset_compiler::建物外形カタログエラー::外部ソースルート不在(_))
    )
}

/// 名指したプロジェクトの置き場から格子の台帳を読む。書き出しは台帳を写し取ってから走るため、試験も同じ形で材料を組む。
pub fn 格子の台帳を読む(プロジェクトルート: &Path) -> blitz_asset_compiler::建物の格子の台帳 {
    let 置き場 = blitz_asset_compiler::建物の格子の置き場::プロジェクトルートから生成する(プロジェクトルート);
    match blitz_asset_compiler::建物の格子の台帳::置き場から読む(&置き場) {
        Ok(台帳) => 台帳,
        Err(原因) => panic!("試験の置き場から格子の台帳を読めない: {原因}"),
    }
}

fn 壁を入れる(種類: &str) -> Value {
    json!({ "種類": "壁を入れる", "値": { "壁の種類": 種類, "外面の飾り": { "種類": "付けない" } } })
}

/// 1升目に骨格を1件据え、4面すべてへ壁を入れ、床を張り屋根を載せた格子。道具が作る初期値と同じ形である。
pub fn 初期の格子のjson() -> Value {
    json!({
        "形式版": 1,
        "建物定義ID": 試験の建物定義の識別子,
        "表示名": "一間四方の家",
        "入口のローカル方向": { "x": 0.0, "z": 1.0 },
        "格子": {
            "根の升目": { "横": 0, "奥": 0, "階": 0 },
            "升目一覧": [{
                "座標": { "横": 0, "奥": 0, "階": 0 },
                "正面": 壁を入れる("扉枠付きの壁"),
                "背面": 壁を入れる("平壁"),
                "左面": 壁を入れる("窓壁"),
                "右面": 壁を入れる("平壁"),
                "床": "張る",
                "屋根": "載せる"
            }]
        },
        "装飾": {}
    })
}

pub fn 升目を空にした格子のjson() -> Value {
    let mut 格子 = 初期の格子のjson();
    格子["格子"]["升目一覧"] = json!([]);
    格子
}

/// 格子から作った建物を1件だけ据えたチャンクの構造。位置はチャンクの中心であり、1ベイの家の外接箱が収まる。
pub fn 格子の建物を1件置いた構造() -> チャンク構造 {
    チャンク構造 {
        道路一覧: Vec::new(),
        建物一覧: vec![建物の配置 {
            識別子: "stable-grid-house-1".to_string(),
            建物定義ID: 試験の建物定義の識別子を作る(),
            位置: 位置3次元 { x: 0.0, y: 999.0, z: 0.0 },
            向きラジアン: 0.25,
            基礎半径メートル: 4.0,
            なじみ半径メートル: 8.0,
        }],
        散布: 散布の設定 {
            最小間隔メートル: 5.5,
            乱数の種: 1,
        },
        散布の個体一覧: Vec::new(),
    }
}

fn 試験の建物定義の識別子を作る() -> editor_server::建物定義ID {
    match editor_server::建物定義ID::生成する(試験の建物定義の識別子) {
        Ok(識別子) => 識別子,
        Err(原因) => panic!("試験の建物定義の識別子が空である: {原因}"),
    }
}
