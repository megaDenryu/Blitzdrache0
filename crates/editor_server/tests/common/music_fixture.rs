//! 楽曲の試験で使う、検証を通る楽曲1件の組み立て。各試験はここから作った楽曲の1箇所だけを崩し、
//! その1箇所が検証に落ちることを見る(落ちた理由が崩した箇所であることを、他が正しいことで保証する)。

use editor_server::{
    コード進行, コード進行参照, トラックの格子, トラックの種類, トラック定義, パターン, パターンID, パターンのステップ数, ミキサー設定, 和音,
    和音の種類, 打楽器の種類, 曲の節, 楽器, 楽曲, 楽曲ID, 楽曲の現在の形式版, 音の並び,
};

pub fn 名乗り(綴り: &str) -> 楽曲ID {
    楽曲ID::生成する(綴り).unwrap()
}

pub fn パターンの名乗り(綴り: &str) -> パターンID {
    パターンID::生成する(綴り).unwrap()
}

/// 指定した行数ぶんの、32ステップすべてが打点なしの格子。
pub fn 打点のない格子(行数: usize) -> トラックの格子 {
    トラックの格子 {
        行一覧: vec![vec![0; パターンのステップ数]; 行数],
    }
}

fn 旋律のトラック() -> トラック定義 {
    トラック定義 {
        表示名: "旋律".to_string(),
        種類: トラックの種類::旋律,
        音の並び: 音の並び::音高の行一覧(vec![72, 71, 69]),
        楽器: 楽器::グランドピアノ,
        音量: 0.8,
        進行の割り当て: Some(コード進行参照::既定の進行 {
            識別子: "王道進行".to_string(),
        }),
    }
}

fn 打楽器のトラック() -> トラック定義 {
    トラック定義 {
        表示名: "打楽器".to_string(),
        種類: トラックの種類::打楽器,
        音の並び: 音の並び::打楽器の行一覧(vec![打楽器の種類::バスドラム, 打楽器の種類::スネア]),
        楽器: 楽器::生ドラム,
        音量: 0.7,
        進行の割り当て: None,
    }
}

pub fn 独自の進行() -> コード進行 {
    コード進行 {
        名前: "試験の進行".to_string(),
        和音一覧: vec![
            和音 {
                根音: 0,
                種類: 和音の種類::長三和音,
                続くステップ数: 16,
            },
            和音 {
                根音: 7,
                種類: 和音の種類::属七の和音,
                続くステップ数: 16,
            },
        ],
    }
}

pub fn 最初のパターン() -> パターン {
    パターン {
        名乗り: パターンの名乗り("最初のパターン"),
        表示名: "最初のパターン".to_string(),
        進行の参照: コード進行参照::独自の進行 {
            名前: "試験の進行".to_string(),
        },
        格子: vec![打点のない格子(3), 打点のない格子(2)],
    }
}

pub fn 楽曲の例() -> 楽曲 {
    楽曲 {
        形式版: 楽曲の現在の形式版,
        名乗り: 名乗り("試験の楽曲"),
        表示名: "試験の楽曲".to_string(),
        拍毎分: 120,
        トラック構成: vec![旋律のトラック(), 打楽器のトラック()],
        ミキサー設定: ミキサー設定 {
            全体の音量: 0.8,
            残響の量: 0.2,
            遅延の量: 0.1,
            遅延のステップ数: 4,
        },
        独自進行一覧: vec![独自の進行()],
        パターン一覧: vec![最初のパターン()],
        曲構成: vec![曲の節 {
            パターンの名乗り: パターンの名乗り("最初のパターン"),
            繰り返し回数: 2,
        }],
    }
}
