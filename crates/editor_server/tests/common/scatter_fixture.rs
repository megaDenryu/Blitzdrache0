//! 散布の書き出しの検査が共有する、道路1本と建物1件と散布の個体5件の下ごしらえ。
//!
//! 個体の位置は、座標の写し違いが検査を素通りしないように選んである。半辺の足し忘れは全個体を16メートル動かし、
//! 南の符号の取り違えは4件目を建物の真上へ、東と南の取り違えは5件目を道路の上へ運ぶ。
//! 1件目・2件目は道路の除外の境界のすぐ外、3件目は建物の除外の境界のすぐ外に置いてある。
#![allow(clippy::unwrap_used)]

use editor_server::{
    チャンクの道路, チャンク座標, チャンク構造, プロジェクト保管庫, 位置3次元, 建物の配置, 散布の個体, 散布の設定, 既定の粗マスの一辺の升目数,
    見下ろし図の下書き,
};

/// 検査に使うチャンクの一辺。`建物を据えられる区画割り`が作る1チャンクの大きさと同じである。
pub const 検査のチャンク一辺メートル: f64 = 32.0;

/// 道路の中心線の端点。z=0の直線であり、制御点が2つのCatmull-Rom曲線は直線になるため、
/// 検査の側は点と線分の距離という独立の式で確かめられる。
pub const 道路の端の東メートル: f64 = 12.0;
pub const 道路の散布除外バッファメートル: f64 = 5.0;

/// 建物の据え位置と、その周りで散布を避ける距離。避ける距離はブラウザの編集モデルと同じ「基礎半径+1」である。
pub const 建物の東: f64 = -8.0;
pub const 建物の南: f64 = -8.0;
pub const 建物の基礎半径メートル: f64 = 3.0;
pub const 建物が散布を避ける距離メートル: f64 = 建物の基礎半径メートル + 1.0;

/// 散布の個体の水平位置。順に、道路のすぐ南・道路のすぐ北・建物のすぐ外・南の符号の見張り・東と南の取り違えの見張りである。
pub const 個体の水平位置一覧: [(f64, f64); 5] = [(-10.0, 5.4), (10.0, -5.4), (-8.0, -12.2), (-8.0, 8.0), (2.0, 10.0)];

pub fn 道路を作る() -> チャンクの道路 {
    チャンクの道路 {
        制御点列: vec![
            位置3次元 {
                x: -道路の端の東メートル,
                y: 0.0,
                z: 0.0,
            },
            位置3次元 {
                x: 道路の端の東メートル,
                y: 0.0,
                z: 0.0,
            },
        ],
        全幅メートル: 4.0,
        散布除外バッファメートル: 道路の散布除外バッファメートル,
        細分割数: 8,
    }
}

pub fn 散布の個体一覧を作る() -> Vec<散布の個体> {
    個体の水平位置一覧
        .iter()
        .enumerate()
        .map(|(添字, (東, 南))| 散布の個体 {
            安定識別子: format!("散布-x0z0-{添字}"),
            チャンク中心からの東メートル: *東,
            チャンク中心からの南メートル: *南,
        })
        .collect()
}

pub fn 散布を載せたチャンク構造を保存する(保管庫: &editor_server::ファイル保管庫, 座標: チャンク座標) {
    let 構造 = チャンク構造 {
        道路一覧: vec![道路を作る()],
        建物一覧: vec![建物の配置 {
            識別子: "stable-house-1".to_string(),
            建物定義ID: editor_server::建物定義ID::生成する(super::一間四方の家の識別子).unwrap(),
            位置: 位置3次元 {
                x: 建物の東,
                y: 0.0,
                z: 建物の南,
            },
            向きラジアン: 0.0,
            基礎半径メートル: 建物の基礎半径メートル,
            なじみ半径メートル: 6.0,
        }],
        散布: 散布の設定 {
            最小間隔メートル: 5.5,
            乱数の種: 7,
        },
        散布の個体一覧: 散布の個体一覧を作る(),
        見下ろし図の下書き: 見下ろし図の下書き::空の下書きを作る(既定の粗マスの一辺の升目数),
    };
    保管庫.チャンクの構造を検証して保存する(座標, 構造).unwrap();
}

/// 点と、z=0に沿う道路の中心線との距離。制御点が2つの曲線は直線であるため、点と線分の距離で求まる。
pub fn 道路の中心線までの距離(東: f64, 南: f64) -> f64 {
    let 最も近い東 = 東.clamp(-道路の端の東メートル, 道路の端の東メートル);
    ((東 - 最も近い東).powi(2) + 南.powi(2)).sqrt()
}

pub fn 建物までの距離(東: f64, 南: f64) -> f64 {
    ((東 - 建物の東).powi(2) + (南 - 建物の南).powi(2)).sqrt()
}
