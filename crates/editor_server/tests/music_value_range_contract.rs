//! 値の範囲の定数が、検証が引いている値のまま`編集資源契約.ts`へ出ていることを確かめる。
//!
//! 綴りと値を試験の側でもう一度書くと3つ目の写しになるため、期待する行はRustの定数から組み立てる。
//! ここが見るのは「検証の正本と書き出しが同じ値か」であり、生成物とディスクの一致は契約鮮度検査が見る。
#![cfg(feature = "typescript")]
#![allow(non_snake_case)]

mod common;

use common::楽曲の例;

fn 定数の行(名前: &str, 値: impl std::fmt::Display) -> String {
    format!("export const {名前} = {値} as const;")
}

fn 出るはずの行一覧() -> Vec<String> {
    vec![
        定数の行("パターンのステップ数", editor_server::パターンのステップ数),
        定数の行("拍毎分の下限", editor_server::拍毎分の下限),
        定数の行("拍毎分の上限", editor_server::拍毎分の上限),
        定数の行("曲の節の繰り返し回数の下限", editor_server::曲の節の繰り返し回数の下限),
        定数の行("曲の節の繰り返し回数の上限", editor_server::曲の節の繰り返し回数の上限),
        定数の行("音高番号の下限", editor_server::音高番号の下限),
        定数の行("音高番号の上限", editor_server::音高番号の上限),
        定数の行("和音の根音の下限", editor_server::和音の根音の下限),
        定数の行("和音の根音の上限", editor_server::和音の根音の上限),
        定数の行("和音の続くステップ数の下限", editor_server::和音の続くステップ数の下限),
        定数の行("和音の続くステップ数の上限", editor_server::和音の続くステップ数の上限),
        定数の行("音量と効果の比の下限", editor_server::音量と効果の比の下限),
        定数の行("音量と効果の比の上限", editor_server::音量と効果の比の上限),
        定数の行("遅延のステップ数の下限", editor_server::遅延のステップ数の下限),
        定数の行("遅延のステップ数の上限", editor_server::遅延のステップ数の上限),
    ]
}

#[test]
fn 値の範囲の定数は検証が引く値のまま書き出される() {
    let 本文 = editor_server::編集資源契約の本文を組み立てる();
    for 行 in 出るはずの行一覧() {
        assert!(本文.contains(&行), "編集資源契約に「{行}」が無い");
    }
}

/// 検証を通る値と通らない値の境目が、書き出した定数のとおりであることを楽曲1件で確かめる。
/// 定数だけを直しても検証が付いてこない食い違いを、ここが落とす。
#[test]
fn 書き出した拍毎分の境目は検証の境目と一致する() {
    let 通す = |拍毎分: u32| {
        let mut 対象 = 楽曲の例();
        対象.拍毎分 = 拍毎分;
        対象.検証する().is_ok()
    };
    assert!(通す(editor_server::拍毎分の下限));
    assert!(通す(editor_server::拍毎分の上限));
    assert!(!通す(editor_server::拍毎分の下限 - 1));
    assert!(!通す(editor_server::拍毎分の上限 + 1));
}
