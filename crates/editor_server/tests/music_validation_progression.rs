//! 楽曲の検証のうち、コード進行に掛かる項目(独自進行の名前の重複・和音の値・参照の解決)を確かめる。
#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

mod common;

use editor_server::コード進行参照;

#[test]
fn 独自進行の名前が重複していると拒む() {
    let mut 対象 = common::楽曲の例();
    対象.独自進行一覧.push(common::独自の進行());
    assert!(対象.検証する().is_err());
}

#[test]
fn 和音一覧が空の独自進行は拒む() {
    let mut 対象 = common::楽曲の例();
    対象.独自進行一覧[0].和音一覧 = Vec::new();
    assert!(対象.検証する().is_err());
}

#[test]
fn 根音は11まで受け入れ12を拒む() {
    let mut 通る = common::楽曲の例();
    通る.独自進行一覧[0].和音一覧[0].根音 = 11;
    通る.検証する().unwrap();

    let mut 拒む = common::楽曲の例();
    拒む.独自進行一覧[0].和音一覧[0].根音 = 12;
    assert!(拒む.検証する().is_err());
}

#[test]
fn 続くステップ数は1から32だけを受け入れる() {
    for 値 in [1, 32] {
        let mut 対象 = common::楽曲の例();
        対象.独自進行一覧[0].和音一覧[0].続くステップ数 = 値;
        対象.検証する().unwrap();
    }
    for 値 in [0, 33] {
        let mut 対象 = common::楽曲の例();
        対象.独自進行一覧[0].和音一覧[0].続くステップ数 = 値;
        assert!(対象.検証する().is_err(), "続くステップ数{値}を通してはならない");
    }
}

#[test]
fn 既定の進行の識別子は一覧にあるものだけを受け入れる() {
    for 識別子 in editor_server::既定の進行の識別子一覧 {
        let mut 対象 = common::楽曲の例();
        対象.トラック構成[0].進行の割り当て = Some(コード進行参照::既定の進行 {
            識別子: 識別子.to_string()
        });
        対象.検証する().unwrap();
    }
}

#[test]
fn 一覧に無い既定の進行を指すと拒む() {
    let mut 対象 = common::楽曲の例();
    対象.トラック構成[0].進行の割り当て = Some(コード進行参照::既定の進行 {
        識別子: "存在しない進行".to_string(),
    });
    assert!(対象.検証する().is_err());
}

#[test]
fn 登録されていない独自の進行を指すと拒む() {
    let mut 対象 = common::楽曲の例();
    対象.パターン一覧[0].進行の参照 = コード進行参照::独自の進行 {
        名前: "登録していない進行".to_string(),
    };
    assert!(対象.検証する().is_err());
}
