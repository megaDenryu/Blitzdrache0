//! `ファイル保管庫`の大域世界(構造・高さ格子)の保存往復テスト。
#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

mod common;

use editor_server::{
    プロジェクト保管庫, マザーハイトマップ, 世界の区画割り, 位置3次元, 大域世界構造, 広域道路
};

fn 区画割り例() -> 世界の区画割り {
    世界の区画割り {
        一辺のメートル: 1024.0,
        軸あたりチャンク数: 4,
        チャンクあたり格子解像度: 128,
    }
}

#[test]
fn 大域世界構造は保存前は無しを返す() {
    let (_一時, 保管庫) = common::保管庫を作る("world_structure_none");
    assert!(保管庫.大域世界の構造を読む().unwrap().is_none());
}

#[test]
fn 大域世界構造を保存して読み戻すと一致する() {
    let (_一時, 保管庫) = common::保管庫を作る("world_structure_roundtrip");
    let 構造 = 大域世界構造 {
        区画割り: 区画割り例(),
        広域道路: 広域道路 {
            制御点列: vec![位置3次元 { x: 0.0, y: 1.0, z: 2.0 }],
            全幅メートル: 12.0,
            細分割数: 120,
        },
    };
    保管庫.大域世界の構造を検証して保存する(構造.clone()).unwrap();
    assert_eq!(保管庫.大域世界の構造を読む().unwrap(), Some(構造));
}

#[test]
fn 大域世界構造の区画割りが不正なら保存を拒む() {
    let (_一時, 保管庫) = common::保管庫を作る("world_structure_invalid");
    let 不正な構造 = 大域世界構造 {
        区画割り: 世界の区画割り {
            一辺のメートル: 0.0,
            軸あたりチャンク数: 4,
            チャンクあたり格子解像度: 128,
        },
        広域道路: 広域道路 {
            制御点列: vec![],
            全幅メートル: 12.0,
            細分割数: 120,
        },
    };
    assert!(保管庫.大域世界の構造を検証して保存する(不正な構造).is_err());
    assert!(保管庫.大域世界の構造を読む().unwrap().is_none());
}

#[test]
fn マザーハイトマップを保存して読み戻すとバイト一致する() {
    let (_一時, 保管庫) = common::保管庫を作る("world_heightmap_roundtrip");
    let 頂点数 = 区画割り例().マザーハイトマップの格子解像度().unwrap();
    let バイト長 = usize::try_from(頂点数).unwrap() * usize::try_from(頂点数).unwrap() * 4;
    let バイト列 = vec![7u8; バイト長];
    let 格子 = マザーハイトマップ::生成する(頂点数, バイト列.clone()).unwrap();
    保管庫.大域世界の高さ格子を検証して保存する(格子).unwrap();
    assert_eq!(保管庫.大域世界の高さ格子を読む().unwrap(), Some(バイト列));
}

#[test]
fn マザーハイトマップの寸法不一致は構築時に拒否される() {
    assert!(マザーハイトマップ::生成する(513, vec![0u8; 10]).is_err());
}
