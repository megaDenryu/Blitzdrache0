//! 正本のファイル書き込みが落ちた回に、記憶の台帳が汚れないことを確かめる反証。
//!
//! カタログのファイルの位置へディレクトリを置いて書き込みを必ず落とす。書き込みの前に台帳を確定すると、
//! ディスクに無い格子が一覧と書き出しへ現れる。組み直しまで通す必要があるため、部品の実体を読む。

#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

use crate::common::{初期の格子のjson, 外部アセットの置き場があるか, 試験の建物定義の識別子};
use editor_server::建物の格子;

fn 書き込めないカタログのファイルを構える(
    一時: &crate::common::一時プロジェクト,
) -> blitz_asset_compiler::建物外形カタログのファイル {
    let ファイル =
        blitz_asset_compiler::建物外形カタログのファイル::リポジトリルートから生成する(一時.リポジトリルート().パス());
    std::fs::create_dir_all(ファイル.パス()).unwrap();
    ファイル
}

#[test]
fn カタログを書けなかった保存は台帳を汚さない() {
    if !外部アセットの置き場があるか() {
        println!("外部アセットの置き場が無いため、書き込み失敗の反証をスキップする");
        return;
    }
    let 一時 = crate::common::一時プロジェクト::生成する("building_grid_write_failure");
    let ファイル = 書き込めないカタログのファイルを構える(&一時);
    let mut 保存係 = editor_server::建物の格子の保存係::起動時の材料から生成する(
        &一時.プロジェクトルート(),
        ファイル,
        crate::common::建物外形カタログを作る(),
    )
    .unwrap();
    let 格子: 建物の格子 = serde_json::from_value(初期の格子のjson()).unwrap();

    let 結果 = 保存係.検査して保存する(&格子);

    assert!(結果.is_err(), "ディレクトリを踏んだカタログの書き出しが成功している");
    assert!(保存係.一覧を並べる().is_empty(), "書き込みが落ちたのに台帳へ建物が載っている");
    assert_eq!(保存係.格子の台帳().件数(), 0);
    assert!(
        保存係.格子を読む(&格子.建物定義ID).unwrap().is_some(),
        "格子の正本は書けているはずである(落ちたのはカタログの書き出しである)"
    );
    assert!(
        !保存係
            .現在のカタログ()
            .建物定義一覧
            .iter()
            .any(|定義| 定義.識別子.綴り() == 試験の建物定義の識別子),
        "書き込みが落ちたのに現在のカタログが差し替わっている"
    );
}
