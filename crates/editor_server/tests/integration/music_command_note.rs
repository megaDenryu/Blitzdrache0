//! 打ち込みの5つの操作コマンドの検証を確かめる。指し先が実在するかと、ステップが格子の内側かを見る。
#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

use editor_server::{
    パターンの打点を全部消す, 打ち込みの対象, 打点を消す, 打点を置く, 楽曲編集コマンド, 範囲の打点を消す, 音を伸ばす
};

/// 手本の楽曲はトラック0が旋律で3行、トラック1が打楽器で2行、パターンは「最初のパターン」1件だけである。
fn 対象(パターン: &str, トラックの位置: u32, 行の位置: u32) -> 打ち込みの対象 {
    打ち込みの対象 {
        パターンの名乗り: crate::common::パターンの名乗り(パターン),
        トラックの位置,
        行の位置,
    }
}

fn 手本のパターンの対象(トラックの位置: u32, 行の位置: u32) -> 打ち込みの対象 {
    対象("最初のパターン", トラックの位置, 行の位置)
}

fn 手本の楽曲で検証を通るか(コマンド: 楽曲編集コマンド) -> bool {
    コマンド.検証する(&crate::common::楽曲の例()).is_ok()
}

fn 打点を置くコマンド(対象: 打ち込みの対象, ステップ: u32) -> 楽曲編集コマンド {
    楽曲編集コマンド::打点を置く(打点を置く {
        対象,
        ステップ,
        進行に従うか: true,
    })
}

fn 音を伸ばすコマンド(始まりのステップ: u32, 終わりのステップ: u32) -> 楽曲編集コマンド {
    楽曲編集コマンド::音を伸ばす(音を伸ばす {
        対象: 手本のパターンの対象(0, 0),
        始まりのステップ,
        終わりのステップ,
        進行に従うか: false,
    })
}

#[test]
fn 打点を置くはステップ0から31を受け入れ32を拒む() {
    assert!(手本の楽曲で検証を通るか(打点を置くコマンド(手本のパターンの対象(0, 0), 0)));
    assert!(手本の楽曲で検証を通るか(打点を置くコマンド(手本のパターンの対象(1, 1), 31)));
    assert!(!手本の楽曲で検証を通るか(打点を置くコマンド(手本のパターンの対象(0, 0), 32)));
}

#[test]
fn 打点を置くはトラックと行の位置が構成の外なら拒む() {
    assert!(手本の楽曲で検証を通るか(打点を置くコマンド(手本のパターンの対象(0, 2), 0)));
    assert!(!手本の楽曲で検証を通るか(打点を置くコマンド(手本のパターンの対象(2, 0), 0)));
    assert!(!手本の楽曲で検証を通るか(打点を置くコマンド(手本のパターンの対象(1, 2), 0)));
}

#[test]
fn 打点を置くは実在しないパターンを指すと拒む() {
    assert!(!手本の楽曲で検証を通るか(打点を置くコマンド(対象("無いパターン", 0, 0), 0)));
}

#[test]
fn 打点を消すはステップが格子の内側のときだけ通る() {
    let 通る = 楽曲編集コマンド::打点を消す(打点を消す {
        対象: 手本のパターンの対象(0, 0),
        ステップ: 31,
    });
    let 拒む = 楽曲編集コマンド::打点を消す(打点を消す {
        対象: 手本のパターンの対象(0, 0),
        ステップ: 32,
    });
    assert!(手本の楽曲で検証を通るか(通る));
    assert!(!手本の楽曲で検証を通るか(拒む));
}

#[test]
fn 音を伸ばすは始まりが終わりより後ろなら拒む() {
    assert!(手本の楽曲で検証を通るか(音を伸ばすコマンド(4, 4)));
    assert!(手本の楽曲で検証を通るか(音を伸ばすコマンド(0, 31)));
    assert!(!手本の楽曲で検証を通るか(音を伸ばすコマンド(5, 4)));
    assert!(!手本の楽曲で検証を通るか(音を伸ばすコマンド(0, 32)));
}

#[test]
fn 範囲の打点を消すも同じ範囲の規律に従う() {
    let 通る = 楽曲編集コマンド::範囲の打点を消す(範囲の打点を消す {
        対象: 手本のパターンの対象(1, 0),
        始まりのステップ: 0,
        終わりのステップ: 15,
    });
    let 拒む = 楽曲編集コマンド::範囲の打点を消す(範囲の打点を消す {
        対象: 手本のパターンの対象(1, 0),
        始まりのステップ: 16,
        終わりのステップ: 15,
    });
    assert!(手本の楽曲で検証を通るか(通る));
    assert!(!手本の楽曲で検証を通るか(拒む));
}

#[test]
fn パターンの打点を全部消すは実在するパターンだけを受け入れる() {
    let 通る = パターンの打点を全部消す {
        パターンの名乗り: crate::common::パターンの名乗り("最初のパターン"),
    };
    let 拒む = パターンの打点を全部消す {
        パターンの名乗り: crate::common::パターンの名乗り("無いパターン"),
    };
    assert!(手本の楽曲で検証を通るか(楽曲編集コマンド::パターンの打点を全部消す(
        通る
    )));
    assert!(!手本の楽曲で検証を通るか(楽曲編集コマンド::パターンの打点を全部消す(
        拒む
    )));
}
