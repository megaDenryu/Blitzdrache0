//! `ファイル保管庫`のチャンク(構造・高さ格子・材質重み)の保存往復テスト。
#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

use editor_server::{
    チャンクの道路, チャンクの高さ編集, チャンク座標, チャンク構造, プロジェクト保管庫, 世界の区画割り, 位置3次元, 地表材質の重み, 建物の配置,
    散布の個体, 散布の設定, 既定の粗マスの一辺の升目数, 見下ろし図の下書き,
};

fn 区画割り例() -> 世界の区画割り {
    世界の区画割り {
        一辺のメートル: 1024.0,
        軸あたりチャンク数: 4,
        チャンクあたり格子解像度: 128,
    }
}

#[test]
fn チャンク構造を保存して読み戻すと一致する() {
    let (_一時, 保管庫) = crate::common::保管庫を作る("chunk_structure_roundtrip");
    let 座標 = チャンク座標::生成する(2, -1);
    let 構造 = チャンク構造 {
        道路一覧: vec![チャンクの道路 {
            制御点列: vec![位置3次元 { x: 1.0, y: 0.0, z: 1.0 }],
            全幅メートル: 8.0,
            散布除外バッファメートル: 14.0,
            細分割数: 80,
        }],
        建物一覧: vec![建物の配置 {
            識別子: "poi_house_0001".to_string(),
            建物定義ID: editor_server::建物定義ID::生成する("frame_house_one_bay").unwrap(),
            位置: 位置3次元 { x: 5.0, y: 0.0, z: 5.0 },
            向きラジアン: 0.5,
            基礎半径メートル: 7.0,
            なじみ半径メートル: 14.0,
        }],
        散布: 散布の設定 {
            最小間隔メートル: 5.5,
            乱数の種: 42,
        },
        散布の個体一覧: vec![散布の個体 {
            安定識別子: "散布-x2z-1-0".to_string(),
            チャンク中心からの東メートル: -3.0,
            チャンク中心からの南メートル: 4.5,
        }],
        見下ろし図の下書き: 見下ろし図の下書き::空の下書きを作る(既定の粗マスの一辺の升目数),
    };
    保管庫.チャンクの構造を検証して保存する(座標, 構造.clone()).unwrap();
    assert_eq!(保管庫.チャンクの構造を読む(座標).unwrap(), Some(構造));
}

#[test]
fn 建物のなじみ半径が基礎半径未満なら保存を拒む() {
    let (_一時, 保管庫) = crate::common::保管庫を作る("chunk_structure_building_invalid");
    let 座標 = チャンク座標::生成する(0, 0);
    let 不正な構造 = チャンク構造 {
        道路一覧: vec![チャンクの道路 {
            制御点列: vec![],
            全幅メートル: 8.0,
            散布除外バッファメートル: 14.0,
            細分割数: 80,
        }],
        建物一覧: vec![建物の配置 {
            識別子: "poi_tower_0001".to_string(),
            建物定義ID: editor_server::建物定義ID::生成する("frame_house_two_story").unwrap(),
            位置: 位置3次元 { x: 0.0, y: 0.0, z: 0.0 },
            向きラジアン: 0.0,
            基礎半径メートル: 10.0,
            なじみ半径メートル: 5.0,
        }],
        散布: 散布の設定 {
            最小間隔メートル: 5.5,
            乱数の種: 1,
        },
        散布の個体一覧: Vec::new(),
        見下ろし図の下書き: 見下ろし図の下書き::空の下書きを作る(既定の粗マスの一辺の升目数),
    };
    assert!(保管庫.チャンクの構造を検証して保存する(座標, 不正な構造).is_err());
    assert!(保管庫.チャンクの構造を読む(座標).unwrap().is_none());
}

#[test]
fn チャンクの高さ格子と材質重みを保存して読み戻すとバイト一致する() {
    let (_一時, 保管庫) = crate::common::保管庫を作る("chunk_grids_storage_roundtrip");
    let 座標 = チャンク座標::生成する(1, 1);
    let 頂点数 = 区画割り例().チャンク格子の頂点数().unwrap();
    let 頂点数usize = usize::try_from(頂点数).unwrap();

    let 高さバイト列 = vec![3u8; 頂点数usize * 頂点数usize * 4];
    let 高さ格子 = チャンクの高さ編集::生成する(頂点数, 高さバイト列.clone()).unwrap();
    保管庫.チャンクの高さ格子を検証して保存する(座標, 高さ格子).unwrap();
    assert_eq!(保管庫.チャンクの高さ格子を読む(座標).unwrap(), Some(高さバイト列));

    let 重みバイト列 = [255u8, 0, 0, 0].repeat(頂点数usize * 頂点数usize);
    let 重み = 地表材質の重み::生成する(頂点数, 重みバイト列.clone()).unwrap();
    保管庫.チャンクの材質重みを検証して保存する(座標, 重み).unwrap();
    assert_eq!(保管庫.チャンクの材質重みを読む(座標).unwrap(), Some(重みバイト列));
}
