//! パターンの小節数に掛かる2つの操作コマンド(追加時の小節数、小節数を変える)の検証を確かめる。
#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

use editor_server::{
    コード進行参照, トラックの格子, パターン, パターンの小節数の上限, パターンの小節数を変える, パターンを追加する, 打ち込みの対象, 打点を置く, 楽曲,
    楽曲編集コマンド,
};

fn 手本の楽曲で検証を通るか(コマンド: 楽曲編集コマンド) -> bool {
    コマンド.検証する(&crate::common::楽曲の例()).is_ok()
}

fn 登録済みの進行への参照() -> コード進行参照 {
    コード進行参照::独自の進行 {
        名前: "試験の進行".to_string(),
    }
}

#[test]
fn パターンを追加するは小節数0と上限より大きい値を拒み1と上限は受け入れる() {
    let 追加する小節数で = |小節数: u32| {
        楽曲編集コマンド::パターンを追加する(パターンを追加する {
            名乗り: crate::common::パターンの名乗り("次のパターン"),
            表示名: "次のパターン".to_string(),
            小節数,
            進行の参照: 登録済みの進行への参照(),
        })
    };
    assert!(手本の楽曲で検証を通るか(追加する小節数で(1)));
    assert!(手本の楽曲で検証を通るか(追加する小節数で(パターンの小節数の上限)));
    assert!(!手本の楽曲で検証を通るか(追加する小節数で(0)));
    assert!(!手本の楽曲で検証を通るか(追加する小節数で(パターンの小節数の上限 + 1)));
}

#[test]
fn パターンの小節数を変えるは実在するパターンと範囲内の値だけを受け入れる() {
    let 変える = |名乗り: &str, 新しい小節数: u32| {
        楽曲編集コマンド::パターンの小節数を変える(パターンの小節数を変える {
            名乗り: crate::common::パターンの名乗り(名乗り),
            新しい小節数,
        })
    };
    assert!(手本の楽曲で検証を通るか(変える("最初のパターン", 1)));
    assert!(手本の楽曲で検証を通るか(変える("最初のパターン", パターンの小節数の上限)));
    assert!(手本の楽曲で検証を通るか(変える("最初のパターン", 3)));
    assert!(!手本の楽曲で検証を通るか(変える("最初のパターン", 0)));
    assert!(!手本の楽曲で検証を通るか(
        変える("最初のパターン", パターンの小節数の上限 + 1)
    ));
    assert!(!手本の楽曲で検証を通るか(変える("無いパターン", 3)));
}

/// 手本の楽曲へ、既定より短い小節数1(16ステップ)のパターンを1件足す。共通のfixtureは変えず、
/// この試験だけが指し先のパターンの長さに応じてステップ範囲の上限が変わることを固定するために組む。
fn 小節数1のパターンを足した楽曲() -> 楽曲 {
    let mut 楽曲 = crate::common::楽曲の例();
    楽曲.パターン一覧.push(パターン {
        名乗り: crate::common::パターンの名乗り("1小節のパターン"),
        表示名: "1小節のパターン".to_string(),
        小節数: 1,
        進行の参照: コード進行参照::独自の進行 {
            名前: "試験の進行".to_string(),
        },
        格子: vec![
            トラックの格子 {
                行一覧: vec![vec![0; 16]; 3],
            },
            トラックの格子 {
                行一覧: vec![vec![0; 16]; 2],
            },
        ],
    });
    楽曲
}

fn 打点を置くコマンド(パターンの名乗り: &str, ステップ: u32) -> 楽曲編集コマンド {
    楽曲編集コマンド::打点を置く(打点を置く {
        対象: 打ち込みの対象 {
            パターンの名乗り: crate::common::パターンの名乗り(パターンの名乗り),
            トラックの位置: 0,
            行の位置: 0,
        },
        ステップ,
        進行に従うか: false,
    })
}

/// 判断16: 打点の位置の検証は定数(32)でなく、指し先のパターンの小節数から決まる長さで行う。
/// 定数32のまま戻す壊し方(ステップの上限を小節数から求めない実装)では、小節数1のパターンの
/// ステップ16が誤って通ってしまい、この試験が落ちる。
#[test]
fn 打点を置くのステップ範囲は指し先のパターンの小節数から決まる() {
    let 対象 = 小節数1のパターンを足した楽曲();
    assert!(打点を置くコマンド("1小節のパターン", 15).検証する(&対象).is_ok());
    assert!(打点を置くコマンド("1小節のパターン", 16).検証する(&対象).is_err());
}
