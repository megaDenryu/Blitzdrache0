//! 曲構成の節を増やし変え減らし並べ替え差し込む5つの操作コマンドの検証と、コマンドの直列化と復元の往復を確かめる。
#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

use editor_server::{
    曲の節を並べ替える, 曲の節を削除する, 曲の節を変える, 曲の節を挿入する, 曲の節を追加する, 楽曲編集コマンド
};

fn 手本の楽曲で検証を通るか(コマンド: 楽曲編集コマンド) -> bool {
    コマンド.検証する(&crate::common::楽曲の例()).is_ok()
}

fn 追加(パターン: &str, 繰り返し回数: u32) -> 楽曲編集コマンド {
    楽曲編集コマンド::曲の節を追加する(曲の節を追加する {
        パターンの名乗り: crate::common::パターンの名乗り(パターン),
        繰り返し回数,
    })
}

fn 挿入する(節の位置: u32, パターン: &str, 繰り返し回数: u32) -> 楽曲編集コマンド {
    楽曲編集コマンド::曲の節を挿入する(曲の節を挿入する {
        節の位置,
        パターンの名乗り: crate::common::パターンの名乗り(パターン),
        繰り返し回数,
    })
}

fn 変える(節の位置: u32, 新しい繰り返し回数: u32) -> 楽曲編集コマンド {
    楽曲編集コマンド::曲の節を変える(曲の節を変える {
        節の位置,
        新しいパターンの名乗り: crate::common::パターンの名乗り("最初のパターン"),
        新しい繰り返し回数,
    })
}

/// 手本の楽曲の曲構成は節1つだけであるため、指せる節の位置は0だけである。
#[test]
fn 曲の節を追加するは繰り返し回数1から8と実在するパターンだけを受け入れる() {
    assert!(手本の楽曲で検証を通るか(追加("最初のパターン", 1)));
    assert!(手本の楽曲で検証を通るか(追加("最初のパターン", 8)));
    assert!(!手本の楽曲で検証を通るか(追加("最初のパターン", 0)));
    assert!(!手本の楽曲で検証を通るか(追加("最初のパターン", 9)));
    assert!(!手本の楽曲で検証を通るか(追加("無いパターン", 1)));
}

/// 手本の楽曲の曲構成は節1つだけであり、指せる挿入位置は手前の0と末尾の1(曲構成の長さと同じ)の2つである。
#[test]
fn 曲の節を挿入するは節の位置が曲構成の長さ以下のときだけ通る() {
    assert!(手本の楽曲で検証を通るか(挿入する(0, "最初のパターン", 1)));
    assert!(手本の楽曲で検証を通るか(挿入する(1, "最初のパターン", 1)));
    assert!(手本の楽曲で検証を通るか(挿入する(1, "最初のパターン", 8)));
    assert!(!手本の楽曲で検証を通るか(挿入する(2, "最初のパターン", 1)));
    assert!(!手本の楽曲で検証を通るか(挿入する(0, "無いパターン", 1)));
    assert!(!手本の楽曲で検証を通るか(挿入する(0, "最初のパターン", 0)));
    assert!(!手本の楽曲で検証を通るか(挿入する(0, "最初のパターン", 9)));
}

#[test]
fn 曲の節を変えるは節の位置が曲構成の内側のときだけ通る() {
    assert!(手本の楽曲で検証を通るか(変える(0, 4)));
    assert!(!手本の楽曲で検証を通るか(変える(1, 4)));
    assert!(!手本の楽曲で検証を通るか(変える(0, 9)));
}

#[test]
fn 曲の節を削除するは節の位置が曲構成の内側のときだけ通る() {
    assert!(手本の楽曲で検証を通るか(楽曲編集コマンド::曲の節を削除する(
        曲の節を削除する { 節の位置: 0 }
    )));
    assert!(!手本の楽曲で検証を通るか(楽曲編集コマンド::曲の節を削除する(
        曲の節を削除する { 節の位置: 1 }
    )));
}

#[test]
fn 曲の節を並べ替えるは両端が曲構成の内側のときだけ通る() {
    let 並べ替える = |元の位置, 先の位置| 楽曲編集コマンド::曲の節を並べ替える(曲の節を並べ替える { 元の位置, 先の位置 });
    assert!(手本の楽曲で検証を通るか(並べ替える(0, 0)));
    assert!(!手本の楽曲で検証を通るか(並べ替える(0, 1)));
    assert!(!手本の楽曲で検証を通るか(並べ替える(1, 0)));
}

#[test]
fn 節が2つある楽曲では入れ替えが通る() {
    let mut 対象 = crate::common::楽曲の例();
    対象.曲構成.push(対象.曲構成[0].clone());
    let 並べ替える = 楽曲編集コマンド::曲の節を並べ替える(曲の節を並べ替える {
        元の位置: 1, 先の位置: 0
    });
    assert!(並べ替える.検証する(&対象).is_ok());
    let 外れた先 = 楽曲編集コマンド::曲の節を並べ替える(曲の節を並べ替える {
        元の位置: 0, 先の位置: 2
    });
    assert!(外れた先.検証する(&対象).is_err());
}

#[test]
fn コマンドは種類と値の欄で直列化と復元を往復する() {
    let コマンド = 追加("最初のパターン", 2);
    let 本文 = serde_json::to_value(&コマンド).unwrap();
    assert_eq!(本文["種類"], serde_json::json!("曲の節を追加する"));
    assert_eq!(本文["値"]["繰り返し回数"], serde_json::json!(2));
    let 読み戻し: 楽曲編集コマンド = serde_json::from_value(本文).unwrap();
    assert_eq!(読み戻し, コマンド);
}

#[test]
fn 曲の節を挿入するコマンドは種類と値の欄で直列化と復元を往復する() {
    let コマンド = 挿入する(1, "最初のパターン", 3);
    let 本文 = serde_json::to_value(&コマンド).unwrap();
    assert_eq!(本文["種類"], serde_json::json!("曲の節を挿入する"));
    assert_eq!(本文["値"]["節の位置"], serde_json::json!(1));
    assert_eq!(本文["値"]["繰り返し回数"], serde_json::json!(3));
    let 読み戻し: 楽曲編集コマンド = serde_json::from_value(本文).unwrap();
    assert_eq!(読み戻し, コマンド);
}
