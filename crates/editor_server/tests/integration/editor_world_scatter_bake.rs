//! 書き出した散布の個体が、焼いた実行時形式でインスタンス群になることと、
//! 同じ編集データを2つの出力ルートへ焼いたバイト列が一致することを確かめる。
#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

use blitz_engine::{実行時形式からシーンを読む, 描画形状};

/// 針葉樹の原型は幅3.2メートル・高さ5.6メートルであり、大きさの倍率は0.8から1.6までに収まる。
/// 焼いた個体がこの範囲の外へ出ていれば、大きさの導出か原型の引き当てが壊れている。
const 大きさの下限: f32 = 0.8;
const 大きさの上限: f32 = 1.6;

#[tokio::test]
async fn 散布の個体は個体数と水平位置を保ったインスタンス群として焼かれる() {
    let 一時 = crate::common::散布を載せて書き出す("bake_scatter_instances").await;
    let バイト列 = crate::common::焼いたチャンクのバイト列を読む(&一時);
    let シーン = 実行時形式からシーンを読む(&バイト列).unwrap();
    let 群一覧 = シーン
        .描画対象一覧()
        .iter()
        .filter_map(|対象| match 対象.形状() {
            描画形状::インスタンス群(群) => Some(群),
            描画形状::通常メッシュ(_) | 描画形状::地形LODメッシュ群(_) => None,
        })
        .collect::<Vec<_>>();
    let 散布の群 = 群一覧
        .iter()
        .find(|群| 群.個体数() == crate::common::個体の水平位置一覧.len())
        .unwrap_or_else(|| panic!("散布の個体数と同じ個体数を持つ群が焼かれていない"));
    let 半辺 = crate::common::検査のチャンク一辺メートル * 0.5;
    for (配置, (東, 南)) in 散布の群.配置一覧().iter().zip(crate::common::個体の水平位置一覧) {
        let [焼いた東, _, 焼いた南] = 配置.平行移動();
        位置が一致することを確かめる(f64::from(焼いた東), 東 + 半辺);
        位置が一致することを確かめる(f64::from(焼いた南), 南 + 半辺);
        let 倍率 = 配置.スケール()[0];
        assert!(
            (大きさの下限..=大きさの上限).contains(&倍率),
            "焼いた個体の大きさが範囲の外にある: {倍率}"
        );
    }
}

/// 実行時形式は水平位置を単精度で持つため、倍精度で組んだ期待値とは末尾の桁が食い違う。
/// 単精度の刻みより十分小さい許容差で見て、写し違いだけを捕まえる。
fn 位置が一致することを確かめる(焼いた: f64, 期待: f64) {
    assert!((焼いた - 期待).abs() < 1e-4, "焼いた水平位置が期待と食い違う: {焼いた}と{期待}");
}

#[tokio::test]
async fn 同じ編集データを2つの出力ルートへ焼くとバイト列が一致する() {
    let 一つ目 = crate::common::散布を載せて書き出す("bake_scatter_determinism_a").await;
    let 二つ目 = crate::common::散布を載せて書き出す("bake_scatter_determinism_b").await;
    assert_eq!(
        crate::common::焼いたチャンクのバイト列を読む(&一つ目),
        crate::common::焼いたチャンクのバイト列を読む(&二つ目)
    );
}
