//! 統合テストのルーターへ持たせる建物外形カタログ。空のカタログを持たせると建物定義の実在検査が常に
//! 失敗側へ倒れ、「未知のIDを拒む」検査と「実在するIDを通す」検査を区別できないため、実際に生成される
//! カタログと同じ識別子・同じ外接箱を持つ2件を据える。値は`cargo xtask building-outline-catalog`が
//! 書き出した内容から写した。
#![allow(clippy::unwrap_used)]

use editor_server::{
    ベイ構造, 建物の入口方向, 建物の外接箱, 建物外形カタログ, 建物外形カタログの現在の形式版, 建物外形定義, 建物定義ID, 建物定義の用途,
};

/// 統合テストで据える家屋の建物定義ID。実際のカタログにも同じ綴りで存在する。
pub const 一間四方の家の識別子: &str = "frame_house_one_bay";

/// 実際のカタログには無い綴り。実在検査が拒む側を確かめるために使う。
pub const カタログに無い識別子: &str = "frame_house_never_generated";

pub fn 建物外形カタログを作る() -> 建物外形カタログ {
    建物外形カタログ {
        形式版: 建物外形カタログの現在の形式版,
        建物定義一覧: vec![
            定義を作る(
                一間四方の家の識別子,
                "屋根を載せた一間四方の家",
                ベイ構造 { 横: 1, 奥: 1, 階: 1 },
                建物の外接箱 {
                    最小: [-1.4150453, 0.0, -2.9254546],
                    最大: [1.4150453, 3.6749415, 1.4],
                },
            ),
            定義を作る(
                "frame_house_two_story",
                "屋根を載せた二段の家",
                ベイ構造 { 横: 1, 奥: 1, 階: 2 },
                建物の外接箱 {
                    最小: [-1.4150453, 0.0, -1.4],
                    最大: [1.4150453, 6.2749414, 1.4],
                },
            ),
        ],
    }
}

fn 定義を作る(識別子: &str, 表示名: &str, ベイ: ベイ構造, 外接箱: 建物の外接箱) -> 建物外形定義 {
    建物外形定義 {
        識別子: 建物定義ID::生成する(識別子).unwrap(),
        表示名: 表示名.to_string(),
        用途: 建物定義の用途::家屋,
        部品の識別子一覧: vec!["Mod_Frame_Bay_Single".to_string()],
        ベイ,
        入口のローカル方向: 建物の入口方向 { x: 0.0, z: 1.0 },
        外接箱,
    }
}
