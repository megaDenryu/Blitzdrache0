//! 楽曲の検証のうち、トラック1本に掛かる項目(種類と楽器の組み合わせ・音の並びの種類・音高の範囲・音量)を確かめる。
#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

mod common;

use editor_server::{トラックの種類, 楽器, 音の並び};

#[test]
fn 種類ごとに定めた楽器なら通る() {
    for (種類, 楽器) in [
        (トラックの種類::旋律, 楽器::フルート),
        (トラックの種類::伴奏, 楽器::エレクトリックピアノ),
        (トラックの種類::低音, 楽器::三角波のベース),
    ] {
        let mut 対象 = common::楽曲の例();
        対象.トラック構成[0].種類 = 種類;
        対象.トラック構成[0].楽器 = 楽器;
        対象.検証する().unwrap();
    }
}

#[test]
fn 打楽器のトラックへ旋律の楽器を割り当てると拒む() {
    let mut 対象 = common::楽曲の例();
    対象.トラック構成[1].楽器 = 楽器::フルート;
    assert!(対象.検証する().is_err());
}

#[test]
fn 旋律のトラックへドラムを割り当てると拒む() {
    let mut 対象 = common::楽曲の例();
    対象.トラック構成[0].楽器 = 楽器::生ドラム;
    assert!(対象.検証する().is_err());
}

#[test]
fn 打楽器のトラックの音の並びが音高の行一覧なら拒む() {
    let mut 対象 = common::楽曲の例();
    対象.トラック構成[1].音の並び = 音の並び::音高の行一覧(vec![36, 38]);
    assert!(対象.検証する().is_err());
}

#[test]
fn 旋律のトラックの音の並びが打楽器の行一覧なら拒む() {
    let mut 対象 = common::楽曲の例();
    対象.トラック構成[0].音の並び = 音の並び::打楽器の行一覧(vec![]);
    assert!(対象.検証する().is_err());
}

#[test]
fn 音高番号は127まで受け入れ128を拒む() {
    let mut 通る = common::楽曲の例();
    通る.トラック構成[0].音の並び = 音の並び::音高の行一覧(vec![0, 127, 60]);
    通る.検証する().unwrap();

    let mut 拒む = common::楽曲の例();
    拒む.トラック構成[0].音の並び = 音の並び::音高の行一覧(vec![0, 128, 60]);
    assert!(拒む.検証する().is_err());
}

#[test]
fn トラックの音量は0から1だけを受け入れる() {
    let mut 通る = common::楽曲の例();
    通る.トラック構成[0].音量 = 1.0;
    通る.検証する().unwrap();

    let mut 拒む = common::楽曲の例();
    拒む.トラック構成[0].音量 = 1.000_1;
    assert!(拒む.検証する().is_err());
}
