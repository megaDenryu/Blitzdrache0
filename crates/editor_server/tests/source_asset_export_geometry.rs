//! `ソースアセット書き出しコマンド`が組み立てる高さ格子の幾何を確かめる。担当するのは、
//! 1px重複共有(隣接チャンクの境界頂点が同値)・世界の端の縁クランプ・保存済みチャンク別高さ格子の
//! マザーに対する優先の3点である。RESTの応答形は`source_asset_export_http.rs`が担当する。
#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

mod common;

use blitz_asset_compiler::高さ格子を読み込む;
use editor_server::{
    ソースアセット書き出しコマンド, チャンクの高さ編集, プロジェクト保管庫, 世界ソース出力先, 出力世界名
};

fn 書き出す(一時: &common::一時プロジェクト) {
    let 保管庫 = editor_server::ファイル保管庫::生成する(&一時.プロジェクトルート());
    let 区画割り = common::小さな区画割り();
    common::大域世界を保存する(&保管庫, 区画割り);
    common::マザーを一意な値で保存する(&保管庫, 区画割り);
    let 出力先 = 世界ソース出力先::生成する(&一時.リポジトリルート(), &出力世界名::生成する(None).unwrap());
    ソースアセット書き出しコマンド::生成する(保管庫, 出力先).実行する().unwrap();
}

fn チャンクを読み込む(一時: &common::一時プロジェクト, x: i32, z: i32) -> blitz_asset_compiler::高さ格子 {
    let ファイル名 = format!("editor_terrain_x{x}_z{z}.heightgrid");
    高さ格子を読み込む(&一時.ルート().join("assets/editor_world").join(ファイル名)).unwrap()
}

#[test]
fn 隣接チャンクの境界頂点は同値である() {
    let 一時 = common::一時プロジェクト::生成する("export_seam");
    書き出す(&一時);

    let チャンク0_0 = チャンクを読み込む(&一時, 0, 0);
    let チャンク1_0 = チャンクを読み込む(&一時, 1, 0);
    // チャンク(0,0)のX方向コア右端(格子添字2)とチャンク(1,0)のコア左端(格子添字0)は
    // 同じ大域添字(x=2)を指すため、どのzでも同値になる。
    for z in 0..=2 {
        assert_eq!(チャンク0_0.高さ(2, z).unwrap(), チャンク1_0.高さ(0, z).unwrap());
    }
}

#[test]
fn 世界の端は縁の値へクランプされる() {
    let 一時 = common::一時プロジェクト::生成する("export_edge_clamp");
    書き出す(&一時);

    // チャンク(0,0)のX方向コア左端(格子添字0、大域x=0)は世界の外側の縁であり、
    // 重なりの縁(格子添字-1)は縁クランプにより同じ大域x=0の値を繰り返す。
    let チャンク0_0 = チャンクを読み込む(&一時, 0, 0);
    assert_eq!(チャンク0_0.高さ(-1, 0).unwrap(), チャンク0_0.高さ(0, 0).unwrap());
}

#[test]
fn 保存済みのチャンク別高さ格子はマザーより優先される() {
    let 一時 = common::一時プロジェクト::生成する("export_override");
    let 保管庫 = editor_server::ファイル保管庫::生成する(&一時.プロジェクトルート());
    let 区画割り = common::小さな区画割り();
    common::大域世界を保存する(&保管庫, 区画割り);
    common::マザーを一意な値で保存する(&保管庫, 区画割り);

    // チャンク(0,0)の3x3(=解像度2+1)を、マザーと重ならない一意な値で上書き保存する。
    let 上書き値: [f32; 9] = [100.0, 101.0, 102.0, 103.0, 104.0, 105.0, 106.0, 107.0, 108.0];
    let mut バイト列 = Vec::new();
    for 値 in 上書き値 {
        バイト列.extend_from_slice(&値.to_le_bytes());
    }
    let 座標 = editor_server::チャンク座標::生成する(0, 0);
    保管庫
        .チャンクの高さ格子を検証して保存する(座標, チャンクの高さ編集::生成する(3, バイト列).unwrap())
        .unwrap();

    let 出力先 = 世界ソース出力先::生成する(&一時.リポジトリルート(), &出力世界名::生成する(None).unwrap());
    ソースアセット書き出しコマンド::生成する(保管庫, 出力先).実行する().unwrap();

    let チャンク0_0 = チャンクを読み込む(&一時, 0, 0);
    for z in 0..3i32 {
        for x in 0..3i32 {
            let 添字 = usize::try_from(z * 3 + x).unwrap();
            assert_eq!(チャンク0_0.高さ(x, z).unwrap(), 上書き値[添字]);
        }
    }
    // 重なりの縁(格子添字-1)は上書きに含まれないため、マザーの値のまま(縁クランプ済みの0)である。
    assert_eq!(チャンク0_0.高さ(-1, 0).unwrap(), 0.0);
}
