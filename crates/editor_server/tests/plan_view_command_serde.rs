//! 見下ろし図の編集コマンド8枝が、`種類`と`値`の判別共用体としてJSONを往復することを確かめる。
//! 参照: `_doc/設計/見下ろし図による地形編集.md`「判断2」
#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

use editor_server::{
    チャンク座標, 地表材質層, 大升から地形を生成する, 大升の塗り, 大升を塗る, 平面の位置, 等高線, 等高線から高さ場を生成する, 等高線を削除する,
    等高線を変更する, 等高線を追加する, 編集コマンド, 高さ場から大升を導く, 高さ場から等高線を導く,
};

fn 等高線の例() -> 等高線 {
    等高線 {
        高さメートル: 4.0,
        頂点列: vec![平面の位置 { x: 1.0, z: -1.0 }, 平面の位置 { x: 2.5, z: 3.0 }],
        閉じている: false,
    }
}

fn 見下ろし図のコマンド8枝() -> Vec<編集コマンド> {
    let チャンク座標 = チャンク座標::生成する(2, -3);
    vec![
        編集コマンド::等高線を追加する(等高線を追加する {
            チャンク座標,
            等高線: 等高線の例(),
        }),
        編集コマンド::等高線を変更する(等高線を変更する {
            チャンク座標,
            添字: 1,
            等高線: 等高線の例(),
        }),
        編集コマンド::等高線を削除する(等高線を削除する {
            チャンク座標, 添字: 0
        }),
        編集コマンド::大升を塗る(大升を塗る {
            チャンク座標,
            大升の一辺の升目数: 8,
            塗り一覧: vec![大升の塗り {
                列: 3,
                行: 4,
                高さメートル: None,
                層: Some(地表材質層::砂),
            }],
        }),
        編集コマンド::等高線から高さ場を生成する(等高線から高さ場を生成する { チャンク座標 }),
        編集コマンド::大升から地形を生成する(大升から地形を生成する { チャンク座標 }),
        編集コマンド::高さ場から等高線を導く(高さ場から等高線を導く {
            チャンク座標,
            間隔メートル: 2.0,
        }),
        編集コマンド::高さ場から大升を導く(高さ場から大升を導く {
            チャンク座標,
            大升の一辺の升目数: 16,
        }),
    ]
}

#[test]
fn 見下ろし図のコマンド8枝はJSONを往復して一致する() {
    for コマンド in 見下ろし図のコマンド8枝() {
        let json = serde_json::to_value(&コマンド).unwrap();
        assert!(json.get("種類").is_some(), "種類の札が無い: {json}");
        let 戻り: 編集コマンド = serde_json::from_value(json).unwrap();
        assert_eq!(戻り, コマンド);
    }
}

#[test]
fn 大升を塗るの札は枝の名前と同じ綴りである() {
    let json = serde_json::to_value(&見下ろし図のコマンド8枝()[3]).unwrap();
    assert_eq!(json["種類"], "大升を塗る");
    assert_eq!(json["値"]["塗り一覧"][0]["層"], "砂");
    assert!(json["値"]["塗り一覧"][0]["高さメートル"].is_null());
}
