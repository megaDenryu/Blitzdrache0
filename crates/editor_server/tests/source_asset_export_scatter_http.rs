//! 保存した散布の個体が、明示の書き出しでチャンクソースへ届く境界を確かめる。
//! 件数と識別子と座標の往復と、道路と建物からの距離の独立検算の2つを見る。
//! 焼いた実行時形式の検査は`editor_world_scatter_bake`が持つ。
#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

mod common;

#[tokio::test]
async fn 保存した散布の個体は件数も識別子も座標も変えずに書き出される() {
    let 一時 = common::散布を載せて書き出す("export_scatter_roundtrip").await;
    let ソース = common::書き出したチャンクソースを読む(&一時);
    assert_eq!(ソース.形式版, 3);
    assert_eq!(ソース.散布の群一覧.len(), 1);
    let 群 = &ソース.散布の群一覧[0];
    assert_eq!(群.植生定義ID, "conifer");
    let 保存した一覧 = common::散布の個体一覧を作る();
    assert_eq!(群.個体一覧.len(), 保存した一覧.len());
    let 半辺 = common::検査のチャンク一辺メートル * 0.5;
    for (書き出した, 保存した) in 群.個体一覧.iter().zip(&保存した一覧) {
        assert_eq!(書き出した.配置識別子, 保存した.安定識別子);
        位置が一致することを確かめる(書き出した.チャンク原点からの東メートル, 保存した.チャンク中心からの東メートル + 半辺);
        位置が一致することを確かめる(書き出した.チャンク原点からの南メートル, 保存した.チャンク中心からの南メートル + 半辺);
    }
}

/// 書き出したJSONは水平位置を単精度で持つため、倍精度で組んだ期待値とは末尾の桁が食い違う。
/// 単精度の刻みより十分小さい許容差で見て、写し違いだけを捕まえる。
fn 位置が一致することを確かめる(書き出した: f64, 期待: f64) {
    assert!(
        (書き出した - 期待).abs() < 1e-4,
        "書き出した水平位置が期待と食い違う: {書き出した}と{期待}"
    );
}

/// 書き出したJSONだけを材料に、道路と建物から離れているかを独立の式で数え直す。
/// 編集モデルは中心線の標本点までの距離で除外を決め、この検査は線分までの距離で見る。標本の刻みは
/// 24メートルを16に割った1.5メートルであり、線分上のどの点も0.75メートル以内に標本を持つ。
/// 除外の距離5メートルとの差は`5 - sqrt(5^2 - 0.75^2)`で0.06メートル未満に収まるため、0.1メートルを引いて見る。
#[tokio::test]
async fn 書き出した散布の個体は道路と建物から離れている() {
    let 一時 = common::散布を載せて書き出す("export_scatter_exclusion").await;
    let 半辺 = common::検査のチャンク一辺メートル * 0.5;
    let 標本の刻みの余裕 = 0.1;
    for 個体 in &common::書き出したチャンクソースを読む(&一時).散布の群一覧[0].個体一覧 {
        let 東 = 個体.チャンク原点からの東メートル - 半辺;
        let 南 = 個体.チャンク原点からの南メートル - 半辺;
        let 道路までの距離 = common::道路の中心線までの距離(東, 南);
        assert!(
            道路までの距離 >= common::道路の散布除外バッファメートル - 標本の刻みの余裕,
            "{}が道路へ寄りすぎている: {道路までの距離}",
            個体.配置識別子
        );
        let 建物までの距離 = common::建物までの距離(東, 南);
        assert!(
            建物までの距離 >= common::建物が散布を避ける距離メートル,
            "{}が建物へ寄りすぎている: {建物までの距離}",
            個体.配置識別子
        );
    }
}
