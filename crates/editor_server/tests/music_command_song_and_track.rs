//! 楽曲全体の設定とトラックの設定を変える6つの操作コマンドの検証を確かめる。
#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

mod common;

use editor_server::{
    コード進行参照, トラックの楽器を変える, トラックの進行の割り当てを変える, トラックの音量を変える, ミキサー設定, ミキサー設定を変える,
    拍毎分を変える, 楽器, 楽曲の表示名を変える, 楽曲編集コマンド,
};

fn 手本の楽曲で検証を通るか(コマンド: 楽曲編集コマンド) -> bool {
    コマンド.検証する(&common::楽曲の例()).is_ok()
}

fn 拍毎分(新しい拍毎分: u32) -> 楽曲編集コマンド {
    楽曲編集コマンド::拍毎分を変える(拍毎分を変える { 新しい拍毎分 })
}

fn 楽器の割り当て(トラックの位置: u32, 新しい楽器: 楽器) -> 楽曲編集コマンド {
    楽曲編集コマンド::トラックの楽器を変える(トラックの楽器を変える {
        トラックの位置, 新しい楽器
    })
}

fn 音量(トラックの位置: u32, 新しい音量: f64) -> 楽曲編集コマンド {
    楽曲編集コマンド::トラックの音量を変える(トラックの音量を変える {
        トラックの位置, 新しい音量
    })
}

fn 進行の割り当て(トラックの位置: u32, 新しい進行の割り当て: Option<コード進行参照>) -> 楽曲編集コマンド {
    楽曲編集コマンド::トラックの進行の割り当てを変える(トラックの進行の割り当てを変える {
        トラックの位置,
        新しい進行の割り当て,
    })
}

#[test]
fn 拍毎分を変えるは40から300を受け入れその外を拒む() {
    assert!(手本の楽曲で検証を通るか(拍毎分(40)));
    assert!(手本の楽曲で検証を通るか(拍毎分(300)));
    assert!(!手本の楽曲で検証を通るか(拍毎分(39)));
    assert!(!手本の楽曲で検証を通るか(拍毎分(301)));
}

#[test]
fn ミキサー設定を変えるは比が0から1の外なら拒む() {
    let 設定を作る = |全体の音量: f64| {
        楽曲編集コマンド::ミキサー設定を変える(ミキサー設定を変える {
            新しいミキサー設定: ミキサー設定 {
                全体の音量,
                残響の量: 0.2,
                遅延の量: 0.1,
                遅延のステップ数: 4,
            },
        })
    };
    assert!(手本の楽曲で検証を通るか(設定を作る(1.0)));
    assert!(!手本の楽曲で検証を通るか(設定を作る(1.5)));
}

#[test]
fn トラックの楽器を変えるは種類が受け入れる楽器だけを通す() {
    assert!(手本の楽曲で検証を通るか(楽器の割り当て(0, 楽器::フルート)));
    assert!(手本の楽曲で検証を通るか(楽器の割り当て(1, 楽器::矩形波と雑音のドラム)));
    assert!(!手本の楽曲で検証を通るか(楽器の割り当て(0, 楽器::生ドラム)));
    assert!(!手本の楽曲で検証を通るか(楽器の割り当て(1, 楽器::フルート)));
}

#[test]
fn トラックの位置が構成の外なら拒む() {
    assert!(!手本の楽曲で検証を通るか(楽器の割り当て(2, 楽器::フルート)));
    assert!(!手本の楽曲で検証を通るか(音量(2, 0.5)));
    assert!(!手本の楽曲で検証を通るか(進行の割り当て(2, None)));
}

#[test]
fn トラックの音量を変えるは0から1を受け入れその外を拒む() {
    assert!(手本の楽曲で検証を通るか(音量(0, 0.0)));
    assert!(手本の楽曲で検証を通るか(音量(0, 1.0)));
    assert!(!手本の楽曲で検証を通るか(音量(0, 1.1)));
    assert!(!手本の楽曲で検証を通るか(音量(0, f64::NAN)));
}

#[test]
fn トラックの進行の割り当てを変えるは無しを受け入れ解決できない参照を拒む() {
    assert!(手本の楽曲で検証を通るか(進行の割り当て(0, None)));
    assert!(手本の楽曲で検証を通るか(進行の割り当て(
        0,
        Some(コード進行参照::既定の進行 {
            識別子: "王道進行".to_string()
        })
    )));
    assert!(!手本の楽曲で検証を通るか(進行の割り当て(
        0,
        Some(コード進行参照::独自の進行 {
            名前: "登録していない進行".to_string()
        })
    )));
}

#[test]
fn 楽曲の表示名を変えるは空白だけの表示名を拒む() {
    let 表示名を変える = |新しい表示名: &str| {
        楽曲編集コマンド::楽曲の表示名を変える(楽曲の表示名を変える {
            新しい表示名: 新しい表示名.to_string(),
        })
    };
    assert!(手本の楽曲で検証を通るか(表示名を変える("名前を付け直した楽曲")));
    assert!(!手本の楽曲で検証を通るか(表示名を変える(" 	 ")));
}
