//! 備え付けのコード進行8件が、試作`_doc/ゲーム開発用エディター計画/シーケンサー.html`の`PROG_PRESETS`と
//! 一致することを確かめる。期待値はこの試験が手で当てたものであり、実装の写しではない。
#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

use editor_server::{和音の種類, 既定のコード進行, 既定のコード進行一覧};

/// 試作の`ch()`は全件で`steps`に4を渡している。
const 試作の1和音のステップ数: u32 = 4;

fn 進行を引く(識別子: &str) -> 既定のコード進行 {
    既定のコード進行一覧()
        .into_iter()
        .find(|進行| 進行.識別子 == 識別子)
        .unwrap_or_else(|| panic!("備え付けの進行に{識別子}が無い"))
}

fn 根音と種類の並び(識別子: &str) -> Vec<(u8, 和音の種類)> {
    進行を引く(識別子).和音一覧.into_iter().map(|和音| (和音.根音, 和音.種類)).collect()
}

#[test]
fn 識別子は仕様の8件である() {
    let 識別子一覧: Vec<String> = 既定のコード進行一覧().into_iter().map(|進行| 進行.識別子).collect();
    assert_eq!(
        識別子一覧,
        vec![
            "戦闘と道",
            "王道進行",
            "街とやすらぎ",
            "カノン進行",
            "小室進行",
            "哀愁進行",
            "冒険",
            "ブルース"
        ]
    );
}

#[test]
fn 各進行は8和音で1和音あたり4ステップである() {
    for 進行 in 既定のコード進行一覧() {
        assert_eq!(進行.和音一覧.len(), 8, "{}の和音の数", 進行.識別子);
        for 和音 in &進行.和音一覧 {
            assert_eq!(和音.続くステップ数, 試作の1和音のステップ数, "{}のステップ数", 進行.識別子);
        }
    }
}

#[test]
fn 表示名は識別子で始まり和音の並びを添える() {
    for 進行 in 既定のコード進行一覧() {
        assert!(進行.表示名.starts_with(&進行.識別子), "{}の表示名: {}", 進行.識別子, 進行.表示名);
    }
}

/// 試作の`canon`。8和音すべてが異なる並びであり、繰り返しでごまかせない1件である(C-G-Am-Em-F-C-F-G)。
#[test]
fn カノン進行は試作と同じ根音と種類の並びを持つ() {
    use 和音の種類::{短三和音, 長三和音};
    assert_eq!(
        根音と種類の並び("カノン進行"),
        vec![
            (0, 長三和音),
            (7, 長三和音),
            (9, 短三和音),
            (4, 短三和音),
            (5, 長三和音),
            (0, 長三和音),
            (5, 長三和音),
            (7, 長三和音)
        ]
    );
}

/// 試作の`blues`。属七の和音だけで組まれた唯一の1件である(A7-D7-A7-E7 を2回)。
#[test]
fn ブルースは試作と同じ根音と種類の並びを持つ() {
    let 属七 = 和音の種類::属七の和音;
    assert_eq!(
        根音と種類の並び("ブルース"),
        vec![(9, 属七), (2, 属七), (9, 属七), (4, 属七), (9, 属七), (2, 属七), (9, 属七), (4, 属七)]
    );
}

/// 試作の`pokemonRoute`。Am-F-G-Em を2回であり、後半が前半の写しであることまで見る。
#[test]
fn 戦闘と道は前半と後半が同じ並びである() {
    let 並び = 根音と種類の並び("戦闘と道");
    use 和音の種類::{短三和音, 長三和音};
    assert_eq!(並び[..4], [(9, 短三和音), (5, 長三和音), (7, 長三和音), (4, 短三和音)]);
    assert_eq!(並び[..4], 並び[4..]);
}
