//! パターンと独自の進行を増やし減らす6つの操作コマンドの検証を確かめる。
#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

mod common;

use editor_server::{
    コード進行, コード進行参照, パターンの表示名を変える, パターンの進行を変える, パターンを削除する, パターンを追加する, 楽曲編集コマンド,
    独自の進行を保存する, 独自の進行を削除する,
};

fn 手本の楽曲で検証を通るか(コマンド: 楽曲編集コマンド) -> bool {
    コマンド.検証する(&common::楽曲の例()).is_ok()
}

fn 登録済みの進行への参照() -> コード進行参照 {
    コード進行参照::独自の進行 {
        名前: "試験の進行".to_string(),
    }
}

fn 追加(名乗り: &str, 表示名: &str, 進行の参照: コード進行参照) -> 楽曲編集コマンド {
    楽曲編集コマンド::パターンを追加する(パターンを追加する {
        名乗り: common::パターンの名乗り(名乗り),
        表示名: 表示名.to_string(),
        進行の参照,
    })
}

#[test]
fn パターンを追加するは未使用の名乗りだけを受け入れる() {
    assert!(手本の楽曲で検証を通るか(
        追加("次のパターン", "次のパターン", 登録済みの進行への参照())
    ));
    assert!(!手本の楽曲で検証を通るか(追加(
        "最初のパターン",
        "重なる名乗り",
        登録済みの進行への参照()
    )));
}

#[test]
fn パターンを追加するは表示名の空と解決できない参照を拒む() {
    assert!(!手本の楽曲で検証を通るか(
        追加("次のパターン", "  ", 登録済みの進行への参照())
    ));
    let 解決できない参照 = コード進行参照::既定の進行 {
        識別子: "無い進行".to_string(),
    };
    assert!(!手本の楽曲で検証を通るか(
        追加("次のパターン", "次のパターン", 解決できない参照)
    ));
}

#[test]
fn パターンを削除するは実在するパターンだけを受け入れる() {
    let 通る = パターンを削除する {
        名乗り: common::パターンの名乗り("最初のパターン"),
    };
    let 拒む = パターンを削除する {
        名乗り: common::パターンの名乗り("無いパターン"),
    };
    assert!(手本の楽曲で検証を通るか(楽曲編集コマンド::パターンを削除する(通る)));
    assert!(!手本の楽曲で検証を通るか(楽曲編集コマンド::パターンを削除する(拒む)));
}

#[test]
fn パターンの進行を変えるは解決できる参照だけを受け入れる() {
    let 進行を変える = |参照| {
        楽曲編集コマンド::パターンの進行を変える(パターンの進行を変える {
            名乗り: common::パターンの名乗り("最初のパターン"),
            新しい進行の参照: 参照,
        })
    };
    assert!(手本の楽曲で検証を通るか(進行を変える(コード進行参照::既定の進行 {
        識別子: "カノン進行".to_string()
    })));
    assert!(!手本の楽曲で検証を通るか(進行を変える(コード進行参照::既定の進行 {
        識別子: "無い進行".to_string()
    })));
}

#[test]
fn パターンの表示名を変えるは空白だけの表示名を拒む() {
    let 表示名を変える = |新しい表示名: &str| {
        楽曲編集コマンド::パターンの表示名を変える(パターンの表示名を変える {
            名乗り: common::パターンの名乗り("最初のパターン"),
            新しい表示名: 新しい表示名.to_string(),
        })
    };
    assert!(手本の楽曲で検証を通るか(表示名を変える("第1のパターン")));
    assert!(!手本の楽曲で検証を通るか(表示名を変える(" ")));
}

#[test]
fn 独自の進行を保存するは進行そのものの不変条件を見る() {
    let 保存する = |進行: コード進行| 楽曲編集コマンド::独自の進行を保存する(独自の進行を保存する { 進行 });
    assert!(手本の楽曲で検証を通るか(保存する(common::独自の進行())));
    let mut 和音の無い進行 = common::独自の進行();
    和音の無い進行.和音一覧 = Vec::new();
    assert!(!手本の楽曲で検証を通るか(保存する(和音の無い進行)));
}

#[test]
fn 独自の進行を削除するは実在する名前だけを受け入れる() {
    let 削除する = |名前: &str| 楽曲編集コマンド::独自の進行を削除する(独自の進行を削除する { 名前: 名前.to_string() });
    assert!(手本の楽曲で検証を通るか(削除する("試験の進行")));
    assert!(!手本の楽曲で検証を通るか(削除する("登録していない進行")));
}
