//! アセットコンパイラが生成する建物外形カタログを、編集サーバーの型がそのまま読み戻せることを確かめる。
//! 生産側と消費側はクレートが分かれており、キーの綴りと形式版はコメントでしか結ばれていない。
//! 片方だけを直した食い違いは、編集サーバーの起動時まで表に出ない。ここが機械的に見る。
#![allow(clippy::unwrap_used)]
#![allow(non_snake_case)]

use blitz_asset_compiler::{建物外形カタログのファイル, 建物外形カタログを組み立てる, 建物外形カタログエラー};
use editor_server::{建物外形カタログ, 建物定義の用途};

/// 建物定義の総数と、そのうち通常の配置操作へ出す家屋の数。正本(`definition_source.rs`)の初版の構成であり、
/// 判断10が「骨格見本2件と家屋3件の計5件」と定めている。
const 定義の件数: usize = 5;
const 家屋の件数: usize = 3;

#[test]
fn 生成したカタログを編集サーバーの型で読み戻すと定義5件と家屋3件になる() {
    let Some(生成したカタログ) = 実体から組み立てる() else {
        return;
    };
    let 一時ディレクトリ = std::env::temp_dir().join(format!("editor_server_catalog_contract_{}", std::process::id()));
    let ファイル = 建物外形カタログのファイル::生成する(一時ディレクトリ.join("building_outline_catalog.json"));
    ファイル.書き出す(&生成したカタログ).unwrap();

    let 読み戻したカタログ = 建物外形カタログ::ファイルから読み取る(ファイル.パス()).unwrap();
    let _ = std::fs::remove_dir_all(&一時ディレクトリ);

    assert_eq!(読み戻したカタログ.建物定義一覧.len(), 定義の件数);
    let 家屋 = 読み戻したカタログ
        .建物定義一覧
        .iter()
        .filter(|定義| 定義.用途 == 建物定義の用途::家屋)
        .count();
    assert_eq!(家屋, 家屋の件数);
    for 定義 in &読み戻したカタログ.建物定義一覧 {
        assert!(!定義.部品の識別子一覧.is_empty(), "{}が据えた部品を1件も持たない", 定義.識別子);
        assert!(定義.外接箱.最大[1] > 定義.外接箱.最小[1], "{}の外接箱に高さが無い", 定義.識別子);
    }
}

/// 外部アセットの置き場は複製できないため、存在しない環境が正当に成立する。置き場が無いときだけ検査を飛ばし、
/// それ以外の失敗は握り潰さずに落とす(参照: `crates/blitz_asset_compiler/src/runtime_compilation/source_location.rs`)。
fn 実体から組み立てる() -> Option<blitz_asset_compiler::建物外形カタログ> {
    match 建物外形カタログを組み立てる() {
        Ok(カタログ) => Some(カタログ),
        Err(建物外形カタログエラー::外部ソースルート不在(診断)) => {
            println!("外部アセットの置き場が無いため、建物外形カタログの契約検査をスキップする: {診断}");
            None
        }
        Err(原因) => panic!("建物外形カタログを組み立てられない: {原因}"),
    }
}
