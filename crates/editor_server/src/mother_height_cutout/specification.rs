//! 区画割りから高さ格子の諸元を組む工程。受け取るのは世界の区画割りで、返すのは
//! 辺分割数・重なり幅・チャンク一辺メートルを備えた諸元である。
//!
//! 重なり幅をここで決めるのは、書き出しが焼く窓と未保存チャンクへ配る初期値の窓が
//! 同じ規則で切り出されることを1箇所で保証するためである。

use blitz_asset_compiler::高さ格子諸元;

use super::chunk_edge_length;
use super::error::高さの切り出しエラー;
use crate::resource::世界の区画割り;

/// 中央差分の法線には隣の1点があれば足りるため、重なりの帯は1格子でよい。
const 重なり幅: u8 = 1;

pub(crate) fn 高さ格子諸元を区画割りから組む(
    区画割り: 世界の区画割り
) -> Result<高さ格子諸元, 高さの切り出しエラー> {
    let 辺分割数 = 辺分割数へ変換する(区画割り.チャンクあたり格子解像度)?;
    let チャンク一辺メートル = chunk_edge_length::求める(区画割り.一辺のメートル, 区画割り.軸あたりチャンク数)?;
    Ok(高さ格子諸元::生成する(辺分割数, 重なり幅, チャンク一辺メートル)?)
}

fn 辺分割数へ変換する(チャンクあたり格子解像度: u32) -> Result<u16, 高さの切り出しエラー> {
    u16::try_from(チャンクあたり格子解像度).map_err(|_| {
        高さの切り出しエラー::数値変換に失敗(format!("チャンクあたり格子解像度がu16へ収まらない: {チャンクあたり格子解像度}"))
    })
}
