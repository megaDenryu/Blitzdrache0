//! 大域のマザーハイトマップから1チャンク分の高さを導く工程を集める。担当するのは、
//! 大域サンプル添字を高さへ写す規則(保存済みのチャンク別高さ編集を優先し、無ければマザーを読み、
//! 世界の外へ出た添字は縁の値へ丸める)と、区画割りから高さ格子の諸元を組むことと、
//! その規則で1チャンク分の高さ編集を切り出すことである。
//!
//! ソースアセットの書き出しと、未保存チャンクの高さ格子を返す経路の両方がここを通る。
//! 導出が2つに分かれると、エディターが開いた高さと焼かれる高さが縁の格子点で食い違い、
//! 焼きの縁の一致検査が落ちる(実測: 重なる帯の格子点で0メートルと2.787967メートル)。
//! 参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断5」

