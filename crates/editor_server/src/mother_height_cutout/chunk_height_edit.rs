//! 未保存のチャンクへ配る高さ編集を、マザーハイトマップから切り出す工程。受け取るのは
//! 区画割りとマザーの生バイト列とチャンク座標で、返すのはそのチャンクの高さ編集である。
//!
//! 書き出しが焼くときと同じ`高さ格子を切り出す`を通すため、隣り合うチャンクが共有する縁の
//! 格子点は同じ大域サンプル添字から読まれ、切り出しだけで必ず一致する。重なりの帯は
//! チャンク単独の編集格子に含まれないため、切り出した窓のうちコアの範囲だけを写す。

use blitz_asset_compiler::高さ格子を切り出す;

use super::chunk_height_sample::高さ関数材料;
use super::error::高さの切り出しエラー;
use super::specification::高さ格子諸元を区画割りから組む;
use crate::resource::{チャンクの高さ編集, チャンク座標, 世界の区画割り};

pub(crate) fn マザーからチャンクの高さ編集を切り出す(
    区画割り: 世界の区画割り,
    マザーバイト列: &[u8],
    座標: チャンク座標,
) -> Result<チャンクの高さ編集, 高さの切り出しエラー> {
    let 諸元 = 高さ格子諸元を区画割りから組む(区画割り)?;
    let 材料 = 高さ関数材料 {
        チャンクx: 座標.x,
        チャンクz: 座標.z,
        解像度: 諸元.辺分割数(),
        マザー一辺頂点数: 区画割り.マザーハイトマップの格子解像度()?,
        マザーバイト列,
        チャンク別バイト列: None,
    };
    let エンジン座標 = blitz_engine::チャンク座標::生成する(座標.x, 座標.z);
    let 窓 = 高さ格子を切り出す(諸元, エンジン座標, |添字x, 添字z| 材料.高さを求める(添字x, 添字z))?;

    let 頂点数 = 区画割り.チャンク格子の頂点数()?;
    let コアの上限 = i32::from(諸元.辺分割数());
    let mut バイト列 = Vec::with_capacity(バイト長を見積もる(頂点数));
    for 格子添字z in 0..=コアの上限 {
        for 格子添字x in 0..=コアの上限 {
            バイト列.extend_from_slice(&窓.高さ(格子添字x, 格子添字z)?.to_le_bytes());
        }
    }
    Ok(チャンクの高さ編集::生成する(頂点数, バイト列)?)
}

/// 事前確保の見積もり。桁あふれしたときは確保量を0へ落とすだけであり、正しさには影響しない。
fn バイト長を見積もる(頂点数: u32) -> usize {
    usize::try_from(頂点数).map(|辺| 辺.saturating_mul(辺).saturating_mul(4)).unwrap_or(0)
}
