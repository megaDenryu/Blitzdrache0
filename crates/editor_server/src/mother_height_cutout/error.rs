//! マザーからの高さの切り出しの型付きエラー。担当するのは、区画割りから諸元を組む工程と
//! 1チャンク分の高さ編集を切り出す工程が失敗しうる理由を1つの語彙へ集めることだけである。

/// 高さの切り出しエラーとは、マザーハイトマップから1チャンク分の高さを導く工程が返しうる失敗の区別のことである。
#[derive(thiserror::Error, Debug)]
pub enum 高さの切り出しエラー {
    #[error("区画割りからの寸法の導出に失敗した: {0}")]
    区画割りの導出に失敗(#[from] crate::resource::資源検証エラー),

    #[error("高さ格子の諸元または切り出しの計算に失敗した: {0}")]
    高さ格子処理に失敗(#[from] blitz_asset_compiler::高さ格子エラー),

    #[error("数値の変換に失敗した: {0}")]
    数値変換に失敗(String),
}
