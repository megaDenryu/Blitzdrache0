//! 経路のパーセント符号を解く純粋な文字列処理。HTTPの型に依存しない
//! （呼び出し連鎖の中の独立した工程。参照: CLAUDE.md「切り出しの根拠義務」第5項。
//! 入力は生の経路文字列、出力は符号を解いた経路文字列）。
//!
//! `%2F`・`%5C`は経路の区切り（`/`・`\`）として解釈される符号であり、これを解くと
//! 経路の区切りが増えて構造が変わってしまう。安全側に倒し、この2つを符号化された形で
//! 含む要求は解かずに拒否する。
//!
//! `normalized_app`の子モジュールとして置く。`経路の符号を解く`・`経路符号を解く際の拒否理由`
//! はどちらも`pub(super)`で`normalized_app`配下だけへ見せる。

/// 経路符号を解く際の拒否理由とは、届いた経路のパーセント符号を解く工程が
/// 要求を拒んだ理由のことである。
#[derive(thiserror::Error, Debug, Clone, PartialEq, Eq)]
pub(super) enum 経路符号を解く際の拒否理由 {
    #[error("経路「{0}」のパーセント符号が壊れている")]
    パーセント符号が壊れている(String),
    #[error("経路「{0}」が符号化された経路区切り（%2Fまたは%5C）を含む")]
    符号化された経路区切りを含む(String),
    #[error("経路「{0}」の符号を解いた結果が正しいUTF-8でない")]
    符号を解いた結果が不正なUtf8(String),
}

/// 経路（問い合わせを含まない部分）のパーセント符号を解く。
pub(super) fn 経路の符号を解く(生の経路: &str) -> Result<String, 経路符号を解く際の拒否理由> {
    let バイト列 = 生の経路.as_bytes();
    let mut 出力バイト列 = Vec::with_capacity(バイト列.len());
    let mut 位置 = 0;
    while 位置 < バイト列.len() {
        if バイト列[位置] == b'%' {
            let 符号値 = 十六進二桁を読む(バイト列, 位置, 生の経路)?;
            拒否すべき区切り符号か確かめる(符号値, 生の経路)?;
            出力バイト列.push(符号値);
            位置 += 3;
        } else {
            出力バイト列.push(バイト列[位置]);
            位置 += 1;
        }
    }
    String::from_utf8(出力バイト列)
        .map_err(|_| 経路符号を解く際の拒否理由::符号を解いた結果が不正なUtf8(生の経路.to_string()))
}

fn 十六進二桁を読む(
    バイト列: &[u8], パーセント位置: usize, 生の経路: &str
) -> Result<u8, 経路符号を解く際の拒否理由> {
    let 上位桁 = バイト列.get(パーセント位置 + 1).copied().and_then(十六進一桁を数値へ変換する);
    let 下位桁 = バイト列.get(パーセント位置 + 2).copied().and_then(十六進一桁を数値へ変換する);
    match (上位桁, 下位桁) {
        (Some(上位), Some(下位)) => Ok(上位 * 16 + 下位),
        _ => Err(経路符号を解く際の拒否理由::パーセント符号が壊れている(
            生の経路.to_string(),
        )),
    }
}

fn 十六進一桁を数値へ変換する(桁: u8) -> Option<u8> {
    match 桁 {
        b'0'..=b'9' => Some(桁 - b'0'),
        b'a'..=b'f' => Some(桁 - b'a' + 10),
        b'A'..=b'F' => Some(桁 - b'A' + 10),
        _ => None,
    }
}

fn 拒否すべき区切り符号か確かめる(符号値: u8, 生の経路: &str) -> Result<(), 経路符号を解く際の拒否理由> {
    if 符号値 == b'/' || 符号値 == b'\\' {
        return Err(経路符号を解く際の拒否理由::符号化された経路区切りを含む(
            生の経路.to_string(),
        ));
    }
    Ok(())
}
