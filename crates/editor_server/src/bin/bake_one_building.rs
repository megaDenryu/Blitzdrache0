//! 建物1棟だけの検証世界のソースを書き出す開発用コマンド。
//! 実行(リポジトリルートで): `cargo xtask bake-building <建物定義ID>`
//!
//! 編集サーバー本体と別のビンにするのは、待受を始めずに1回の書き出しだけを行うためである。
//! 契約の書き出し(`contract_export`)と同じ位置づけであり、どちらも編集サーバーのライブラリを使う一発の道具である。

#![forbid(unsafe_code)]

use editor_server::{
    プロジェクトルートを解決する, リポジトリルート, 一棟だけの検証世界を書き出すコマンド, 世界ソース出力先, 出力世界名, 建物の格子の保存係,
    建物外形カタログ, 建物定義ID,
};

fn main() -> std::process::ExitCode {
    match 書き出す() {
        Ok(綴り) => {
            println!("一棟検証の世界のソース: {綴り}");
            std::process::ExitCode::SUCCESS
        }
        Err(誤り) => {
            eprintln!("[bake-one-building] {誤り}");
            std::process::ExitCode::FAILURE
        }
    }
}

fn 書き出す() -> Result<String, String> {
    let 引数一覧: Vec<String> = std::env::args().skip(1).collect();
    let 建物定義の識別子 = 建物定義の識別子を引数から取り出す(&引数一覧)?;
    let リポジトリルート = リポジトリルート::解決する();
    let プロジェクトルート = プロジェクトルートを解決する(&引数一覧, &リポジトリルート);
    let カタログのファイル = リポジトリルート.建物外形カタログのファイル();
    let カタログ = 建物外形カタログ::ファイルから読み取る(カタログのファイル.パス()).map_err(|原因| 原因.to_string())?;
    let 保存係 = 建物の格子の保存係::起動時の材料から生成する(&プロジェクトルート, カタログのファイル, カタログ).map_err(|原因| 原因.to_string())?;

    let 世界名 = 出力世界名::建物一棟の検証世界を指して生成する().map_err(|原因| 原因.to_string())?;
    let 出力先 = 世界ソース出力先::生成する(&リポジトリルート, &世界名);
    let コマンド =
        一棟だけの検証世界を書き出すコマンド::生成する(出力先, 保存係.現在のカタログ().clone(), 保存係.格子の台帳().clone());
    let 結果 = コマンド.実行する(&建物定義の識別子).map_err(|原因| 原因.to_string())?;
    Ok(format!("{}({}ファイル)", 結果.出力先ディレクトリ(), 結果.書いたファイル数()))
}

/// 建物定義IDは先頭の引数だけから読む。選択肢でない引数を探し回らないのは、`--project <ルート>`の
/// 値のような「選択肢に続く値」を建物定義IDと取り違えないためである。
fn 建物定義の識別子を引数から取り出す(引数一覧: &[String]) -> Result<建物定義ID, String> {
    match 引数一覧.first() {
        Some(先頭) if !先頭.starts_with("--") => 建物定義ID::生成する(先頭.as_str()).map_err(|原因| 原因.to_string()),
        _ => Err("建物定義IDを先頭の引数として渡していない。使い方: bake_one_building <建物定義ID> [--project <ルート>]".to_string()),
    }
}
