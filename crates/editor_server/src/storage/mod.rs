//! プロジェクト保管庫の永続化境界。差し替え可能な保存先の口をtraitとして持ち、
//! 実装は`file_repository`(初期実装、プロジェクトルート配下のファイル)が担う。
//! 参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断2」

mod file_repository;
mod response;

use crate::resource::{
    チャンクの高さ編集, チャンク座標, チャンク構造, マザーハイトマップ, マテリアル台帳, 地表材質の重み, 大域世界構造, 資源検証エラー,
};

pub use file_repository::ファイル保管庫;

/// 読み込みエラーとは、正本ファイルを読んで解釈する際に起きうる失敗のことである。
#[derive(thiserror::Error, Debug)]
pub enum 読み込みエラー {
    #[error("正本ファイルの読み込みに失敗した: {0}")]
    ファイル読み込みに失敗(#[from] std::io::Error),
    #[error("正本ファイルのJSONとしての解釈に失敗した: {0}")]
    Json解釈に失敗(#[from] serde_json::Error),
    #[error("旧版の正本ファイルを最新形式へ移行できない: {0}")]
    旧版移行に失敗(#[from] crate::resource::チャンク構造移行エラー),
}

/// 保存要求エラーとは、`検証して保存する`系メソッドが返しうる失敗の区別のことである。
#[derive(thiserror::Error, Debug)]
pub enum 保存要求エラー {
    #[error("既存の正本を読めないため上書きを拒む: {0}")]
    既存正本を読めない(#[from] 読み込みエラー),
    #[error("受け取った内容が型契約の不変条件を満たさない: {0}")]
    検証に失敗(#[from] 資源検証エラー),
    #[error("JSONの読み書きに失敗した: {0}")]
    Json処理に失敗(#[from] serde_json::Error),
    #[error("正本ファイルへの書き込みに失敗した: {0}")]
    書き込みに失敗(#[from] std::io::Error),
}

/// プロジェクト保管庫とは、編集資源の種別ごとに型付きの読み・検証つき保存の口を持つ、
/// 永続化の差し替え可能な境界のことである。「無し」は`Option`で表す(初回起動はまだ何も無い)。
pub trait プロジェクト保管庫 {
    fn 大域世界の構造を読む(&self) -> Result<Option<大域世界構造>, 読み込みエラー>;
    fn 大域世界の構造を検証して保存する(&self, データ: 大域世界構造) -> Result<(), 保存要求エラー>;

    /// 高さ格子の読みは書き込み済みの生バイト列をそのまま返す。書き込み時点で寸法検証を
    /// 通しているため、読み側で再構成・再検証はしない(実際に使う書き込み時にだけ失敗させる)。
    fn 大域世界の高さ格子を読む(&self) -> Result<Option<Vec<u8>>, 読み込みエラー>;
    fn 大域世界の高さ格子を検証して保存する(&self, 格子: マザーハイトマップ) -> Result<(), 保存要求エラー>;

    fn チャンクの構造を読む(&self, 座標: チャンク座標) -> Result<Option<チャンク構造>, 読み込みエラー>;
    fn チャンクの構造を検証して保存する(
        &self, 座標: チャンク座標, データ: チャンク構造
    ) -> Result<(), 保存要求エラー>;

    fn チャンクの高さ格子を読む(&self, 座標: チャンク座標) -> Result<Option<Vec<u8>>, 読み込みエラー>;
    fn チャンクの高さ格子を検証して保存する(
        &self,
        座標: チャンク座標,
        格子: チャンクの高さ編集,
    ) -> Result<(), 保存要求エラー>;

    fn チャンクの材質重みを読む(&self, 座標: チャンク座標) -> Result<Option<Vec<u8>>, 読み込みエラー>;
    fn チャンクの材質重みを検証して保存する(
        &self, 座標: チャンク座標, 重み: 地表材質の重み
    ) -> Result<(), 保存要求エラー>;

    fn マテリアル台帳を読む(&self) -> Result<Option<マテリアル台帳>, 読み込みエラー>;
    fn マテリアル台帳を検証して保存する(&self, データ: マテリアル台帳) -> Result<(), 保存要求エラー>;
}
