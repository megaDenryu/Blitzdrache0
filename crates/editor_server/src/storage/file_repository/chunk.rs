//! チャンクの構造・高さ格子・材質重みの読み書き。触れるパスは`編集データディレクトリ`が導く
//! チャンク配下の3ファイルだけであり、大域世界側のパスには触れない
//! (切り出しの根拠: 触れるフィールドが限定された操作の分離。参照: CLAUDE.md「切り出しの根拠義務」第3項)。

use super::data_directory::編集データディレクトリ;
use super::json_io::{json構造体を保存する, json構造体を読む, バイナリを保存する, バイナリを読む};
use crate::resource::{
    チャンクの高さ編集, チャンク座標, チャンク構造, 地表材質の重み, 読み込んだチャンク構造の版
};
use crate::storage::{保存要求エラー, 読み込みエラー};

/// 保存済みのJSONは道路が1本だけだった頃の形のこともあるため、版を判別してから最新の形へ変換する
/// (参照: `resource/chunk_structure_version.rs`)。
pub(super) fn 構造を読む(
    ディレクトリ: &編集データディレクトリ,
    座標: チャンク座標,
) -> Result<Option<チャンク構造>, 読み込みエラー> {
    let 読み込んだ版: Option<読み込んだチャンク構造の版> = json構造体を読む(&ディレクトリ.チャンク構造パス(座標))?;
    読み込んだ版
        .map(読み込んだチャンク構造の版::最新の形へ変換する)
        .transpose()
        .map_err(Into::into)
}

/// 上書きの前に既存の正本を読み直し、読めないチャンクへの保存を拒む。移行できない旧版が残っているチャンクは、
/// 画面が中身を読めないまま新しい内容で上書きすると、旧版だけが持っていた建物(塔・宝箱)の位置が復元不能に消える。
pub(super) fn 構造を検証して保存する(
    ディレクトリ: &編集データディレクトリ,
    座標: チャンク座標,
    データ: チャンク構造,
) -> Result<(), 保存要求エラー> {
    構造を読む(ディレクトリ, 座標)?;
    データ.検証する()?;
    json構造体を保存する(&ディレクトリ.チャンク構造パス(座標), &データ)
}

pub(super) fn 高さ格子を読む(
    ディレクトリ: &編集データディレクトリ, 座標: チャンク座標
) -> Result<Option<Vec<u8>>, 読み込みエラー> {
    バイナリを読む(&ディレクトリ.チャンク高さ格子パス(座標))
}

pub(super) fn 高さ格子を検証して保存する(
    ディレクトリ: &編集データディレクトリ,
    座標: チャンク座標,
    格子: チャンクの高さ編集,
) -> Result<(), 保存要求エラー> {
    バイナリを保存する(&ディレクトリ.チャンク高さ格子パス(座標), 格子.バイト列())
}

pub(super) fn 材質重みを読む(
    ディレクトリ: &編集データディレクトリ, 座標: チャンク座標
) -> Result<Option<Vec<u8>>, 読み込みエラー> {
    バイナリを読む(&ディレクトリ.チャンク材質重みパス(座標))
}

pub(super) fn 材質重みを検証して保存する(
    ディレクトリ: &編集データディレクトリ,
    座標: チャンク座標,
    重み: 地表材質の重み,
) -> Result<(), 保存要求エラー> {
    バイナリを保存する(&ディレクトリ.チャンク材質重みパス(座標), 重み.バイト列())
}
