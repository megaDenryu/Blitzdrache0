//! `プロジェクト保管庫`のファイル実装。`<プロジェクトルート>/editor_data/`配下へ、
//! 構造化データはJSON(整形済み)、格子は生バイナリ(.f32raw/.u8raw)で保存する
//! (参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断2」)。
//! 実処理は`world`・`chunk`(触れるパスが互いに独立な私有モジュール)へ委譲する。

mod chunk;
mod data_directory;
mod file_names;
mod json_io;
mod world;

use data_directory::編集データディレクトリ;

use crate::project_root::プロジェクトルート;
use crate::resource::{
    チャンクの高さ編集, チャンク座標, チャンク構造, マザーハイトマップ, 地表材質の重み, 大域世界構造
};
use crate::storage::{プロジェクト保管庫, 保存要求エラー, 読み込みエラー};

/// ファイル保管庫とは、`プロジェクト保管庫`をプロジェクトルート配下のファイルへ読み書きする
/// 実装のことである。保持するのは編集データディレクトリという役割を持つパスの型1つだけであり、
/// 各資源のファイル名の綴りは`編集データディレクトリ`のメソッドと`file_names`だけが知る。
#[derive(Clone)]
pub struct ファイル保管庫 {
    編集データディレクトリ: 編集データディレクトリ,
}

impl ファイル保管庫 {
    pub fn 生成する(プロジェクトルート: &プロジェクトルート) -> Self {
        Self {
            編集データディレクトリ: 編集データディレクトリ::生成する(プロジェクトルート),
        }
    }
}

impl プロジェクト保管庫 for ファイル保管庫 {
    fn 大域世界の構造を読む(&self) -> Result<Option<大域世界構造>, 読み込みエラー> {
        world::構造を読む(&self.編集データディレクトリ)
    }

    fn 大域世界の構造を検証して保存する(&self, データ: 大域世界構造) -> Result<(), 保存要求エラー> {
        world::構造を検証して保存する(&self.編集データディレクトリ, データ)
    }

    fn 大域世界の高さ格子を読む(&self) -> Result<Option<Vec<u8>>, 読み込みエラー> {
        world::高さ格子を読む(&self.編集データディレクトリ)
    }

    fn 大域世界の高さ格子を検証して保存する(&self, 格子: マザーハイトマップ) -> Result<(), 保存要求エラー> {
        world::高さ格子を検証して保存する(&self.編集データディレクトリ, 格子)
    }

    fn チャンクの構造を読む(&self, 座標: チャンク座標) -> Result<Option<チャンク構造>, 読み込みエラー> {
        chunk::構造を読む(&self.編集データディレクトリ, 座標)
    }

    fn チャンクの構造を検証して保存する(
        &self, 座標: チャンク座標, データ: チャンク構造
    ) -> Result<(), 保存要求エラー> {
        chunk::構造を検証して保存する(&self.編集データディレクトリ, 座標, データ)
    }

    fn チャンクの高さ格子を読む(&self, 座標: チャンク座標) -> Result<Option<Vec<u8>>, 読み込みエラー> {
        chunk::高さ格子を読む(&self.編集データディレクトリ, 座標)
    }

    fn チャンクの高さ格子を検証して保存する(
        &self,
        座標: チャンク座標,
        格子: チャンクの高さ編集,
    ) -> Result<(), 保存要求エラー> {
        chunk::高さ格子を検証して保存する(&self.編集データディレクトリ, 座標, 格子)
    }

    fn チャンクの材質重みを読む(&self, 座標: チャンク座標) -> Result<Option<Vec<u8>>, 読み込みエラー> {
        chunk::材質重みを読む(&self.編集データディレクトリ, 座標)
    }

    fn チャンクの材質重みを検証して保存する(
        &self, 座標: チャンク座標, 重み: 地表材質の重み
    ) -> Result<(), 保存要求エラー> {
        chunk::材質重みを検証して保存する(&self.編集データディレクトリ, 座標, 重み)
    }
}
