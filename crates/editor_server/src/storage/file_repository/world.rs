//! 大域世界の構造・高さ格子の読み書き。触れるパスは`編集データディレクトリ`が導く
//! 大域世界配下の2ファイルだけであり、チャンク側のパスには触れない
//! (切り出しの根拠: 触れるフィールドが限定された操作の分離。参照: CLAUDE.md「切り出しの根拠義務」第3項)。

use super::data_directory::編集データディレクトリ;
use super::json_io::{json構造体を保存する, json構造体を読む, バイナリを保存する, バイナリを読む};
use crate::resource::{マザーハイトマップ, 大域世界構造};
use crate::storage::{保存要求エラー, 読み込みエラー};

pub(super) fn 構造を読む(ディレクトリ: &編集データディレクトリ) -> Result<Option<大域世界構造>, 読み込みエラー> {
    json構造体を読む(&ディレクトリ.大域世界構造パス())
}

pub(super) fn 構造を検証して保存する(
    ディレクトリ: &編集データディレクトリ, データ: 大域世界構造
) -> Result<(), 保存要求エラー> {
    データ.検証する()?;
    json構造体を保存する(&ディレクトリ.大域世界構造パス(), &データ)
}

pub(super) fn 高さ格子を読む(ディレクトリ: &編集データディレクトリ) -> Result<Option<Vec<u8>>, 読み込みエラー> {
    バイナリを読む(&ディレクトリ.大域世界高さ格子パス())
}

pub(super) fn 高さ格子を検証して保存する(
    ディレクトリ: &編集データディレクトリ,
    格子: マザーハイトマップ,
) -> Result<(), 保存要求エラー> {
    バイナリを保存する(&ディレクトリ.大域世界高さ格子パス(), 格子.バイト列())
}
