//! 楽曲の読み書き。触れるパスは`編集データディレクトリ`が導く楽曲の置き場1つだけである
//! (切り出しの根拠: 触れるフィールドが限定された操作の分離。参照: CLAUDE.md「切り出しの根拠義務」第3項)。
//!
//! 一覧を置き場の数え上げで作り、見出しの台帳を別に持たないのは、台帳とファイルが食い違う瞬間を作らないためである。
//! 同じ理由で、置き場のファイル名と正本の中の名乗りが食い違うものは読みが拒む
//! (参照: `_doc/設計/楽曲エディター.md`「判断6」)。

use std::ffi::OsStr;
use std::path::Path;

use super::data_directory::編集データディレクトリ;
use super::json_io::{json構造体を保存する, json構造体を読む};
use crate::resource::{楽曲, 楽曲ID, 読み込んだ楽曲の版};
use crate::storage::{保存要求エラー, 読み込みエラー};

pub(super) fn 楽曲の一覧を読む(ディレクトリ: &編集データディレクトリ) -> Result<Vec<楽曲ID>, 読み込みエラー> {
    let 置き場 = ディレクトリ.楽曲ディレクトリ();
    if !置き場.is_dir() {
        return Ok(Vec::new());
    }
    let mut 名乗り一覧 = Vec::new();
    for 項目 in std::fs::read_dir(&置き場)? {
        let パス = 項目?.path();
        if 楽曲の正本のファイルか(&パス) {
            名乗り一覧.push(ファイル名を名乗りとして解く(&パス)?);
        }
    }
    名乗り一覧.sort();
    Ok(名乗り一覧)
}

/// 保存済みのJSONは形式版の欄を持たない旧版のこともあるため、版を判別してから現在の形へ変換する
/// (参照: `resource/music/version.rs`)。
pub(super) fn 楽曲を読む(
    ディレクトリ: &編集データディレクトリ, 名乗り: &楽曲ID
) -> Result<Option<楽曲>, 読み込みエラー> {
    let 読み込んだ版: Option<読み込んだ楽曲の版> = json構造体を読む(&ディレクトリ.楽曲パス(名乗り))?;
    match 読み込んだ版.map(読み込んだ楽曲の版::現在の形へ変換する).transpose()? {
        Some(読んだ楽曲) if &読んだ楽曲.名乗り != 名乗り => Err(読み込みエラー::名乗りとファイル名が食い違う {
            ファイル名: 名乗り.綴り().to_string(),
            名乗り: 読んだ楽曲.名乗り.綴り().to_string(),
        }),
        そのまま返す内容 => Ok(そのまま返す内容),
    }
}

pub(super) fn 楽曲を検証して保存する(
    ディレクトリ: &編集データディレクトリ, データ: 楽曲
) -> Result<(), 保存要求エラー> {
    データ.検証する()?;
    json構造体を保存する(&ディレクトリ.楽曲パス(&データ.名乗り), &データ)
}

/// 置き場に混ざったディレクトリと別の拡張子のファイルは楽曲の正本ではないため、一覧から飛ばす。
fn 楽曲の正本のファイルか(パス: &Path) -> bool {
    パス.is_file() && パス.extension().and_then(OsStr::to_str) == Some("json")
}

/// 正本のファイル名が名乗りとして成り立たないときは飛ばさず拒む。飛ばすと、置き場に在る楽曲が一覧から
/// 黙って消え、同じ名乗りで保存し直したときに既存の正本を上書きする。
fn ファイル名を名乗りとして解く(パス: &Path) -> Result<楽曲ID, 読み込みエラー> {
    let ファイル名 = パス.file_name().map_or_else(String::new, |名前| 名前.to_string_lossy().into_owned());
    let 綴り = パス
        .file_stem()
        .and_then(OsStr::to_str)
        .ok_or_else(|| 読み込みエラー::ファイル名を名乗りとして読めない {
            ファイル名: ファイル名.clone(),
            説明: "ファイル名の文字の並びを解釈できない".to_string(),
        })?;
    楽曲ID::生成する(綴り).map_err(|誤り| 読み込みエラー::ファイル名を名乗りとして読めない {
        ファイル名,
        説明: 誤り.to_string(),
    })
}
