//! マテリアル台帳の読み書き。触れるパスは`編集データディレクトリ`が導く1ファイルだけである
//! (切り出しの根拠: 触れるフィールドが限定された操作の分離。参照: CLAUDE.md「切り出しの根拠義務」第3項)。

use super::data_directory::編集データディレクトリ;
use super::json_io::{json構造体を保存する, json構造体を読む};
use crate::resource::マテリアル台帳;
use crate::storage::{保存要求エラー, 読み込みエラー};

pub(super) fn 読む(ディレクトリ: &編集データディレクトリ) -> Result<Option<マテリアル台帳>, 読み込みエラー> {
    json構造体を読む(&ディレクトリ.マテリアル台帳パス())
}

pub(super) fn 検証して保存する(
    ディレクトリ: &編集データディレクトリ, データ: マテリアル台帳
) -> Result<(), 保存要求エラー> {
    データ.検証する()?;
    json構造体を保存する(&ディレクトリ.マテリアル台帳パス(), &データ)
}
