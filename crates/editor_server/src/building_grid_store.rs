//! 建物の格子の保存係: 格子の置き場・建物外形カタログのファイル・カタログの組み立て係・現在のカタログを保持し、
//! 格子の一覧・読み・検査つき保存をメソッドで公開する操作サービス。
//!
//! 依存を保持させるのは、置き場もカタログのファイルもサーバーが動いている間ずっと同じだからである。
//! 呼び出し側(経路のハンドラ)に持参させると、別のプロジェクトの置き場を渡しても型が通る。
//!
//! 保存が格子のファイルより先にカタログを組み直すのは、組み立てに耐えない格子で正本を書き換えないためである
//! (判断2の保存規律)。組み直しが通ってから格子を書き、そのあとカタログのファイルを差し替える。
//! 参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断2」「判断10」

mod error;

use blitz_asset_compiler::{建物の格子の置き場, 建物外形カタログのファイル, 建物外形カタログの組み立て係};

use crate::project_root::プロジェクトルート;
use crate::resource::{建物の格子, 建物の格子の一覧項目, 建物外形カタログ, 建物定義ID};

pub use error::建物の格子の保存エラー;

pub struct 建物の格子の保存係 {
    置き場: 建物の格子の置き場,
    カタログのファイル: 建物外形カタログのファイル,
    組み立て係: 建物外形カタログの組み立て係,
    現在のカタログ: 建物外形カタログ,
}

impl 建物の格子の保存係 {
    /// 起動時に置き場の全建物を解いてから作る。解けない格子が1件でもあれば型付きエラーで拒み、
    /// 半端な台帳のまま起動しない。
    pub fn 起動時の材料から生成する(
        プロジェクトルート: &プロジェクトルート,
        カタログのファイル: 建物外形カタログのファイル,
        現在のカタログ: 建物外形カタログ,
    ) -> Result<Self, 建物の格子の保存エラー> {
        let 置き場 = 建物の格子の置き場::プロジェクトルートから生成する(プロジェクトルート.パス());
        let 組み立て係 = 建物外形カタログの組み立て係::置き場から台帳を読んで生成する(&置き場)?;
        Ok(Self {
            置き場,
            カタログのファイル,
            組み立て係,
            現在のカタログ,
        })
    }

    /// 保持している格子の置き場を貸す。ソースアセットの書き出しが、チャンクが使う格子を読むために要る。
    pub fn 格子の置き場(&self) -> &建物の格子の置き場 {
        &self.置き場
    }

    pub fn 現在のカタログ(&self) -> &建物外形カタログ {
        &self.現在のカタログ
    }

    /// 保存済みの建物を識別子の昇順で並べる。台帳は起動時と保存時にだけ更新されるため、置き場を読み直さない。
    pub fn 一覧を並べる(&self) -> Vec<建物の格子の一覧項目> {
        self.組み立て係.格子の台帳().昇順に数え上げる().map(一覧項目へ写す).collect()
    }

    /// 名指した建物の格子をファイルから読む。まだ保存されていない建物は「無し」で答える。
    pub fn 格子を読む(&self, 識別子: &建物定義ID) -> Result<Option<serde_json::Value>, 建物の格子の保存エラー> {
        let 識別子 = ソースの識別子へ写す(識別子)?;
        let ファイル = self.置き場.建物定義の格子ファイル(&識別子);
        if !ファイル.パス().is_file() {
            return Ok(None);
        }
        Ok(Some(serde_json::to_value(ファイル.読んで最新の形にする()?)?))
    }

    /// 格子を解いてカタログを組み直し、通ったときだけ正本の2つのファイルを書き換える。
    pub fn 検査して保存する(&mut self, 格子: &建物の格子) -> Result<(), 建物の格子の保存エラー> {
        格子.検証する()?;
        let ソース = 格子.ソースの形へ写す().map_err(建物の格子の保存エラー::ソースの形へ写せない)?;
        let 定義 = ソース.格子由来の建物定義へ解く()?;
        let 組み直したカタログ = self.組み立て係.格子を1件差し替えて組み直す(定義)?;
        self.置き場.建物定義の格子ファイル(&ソース.建物定義ID).書き出す(&ソース)?;
        self.カタログのファイル.書き出す(&組み直したカタログ)?;
        self.現在のカタログ = 建物外形カタログ::ファイルから読み取る(self.カタログのファイル.パス())?;
        Ok(())
    }
}

fn 一覧項目へ写す(定義: &blitz_asset_compiler::格子由来の建物定義) -> 建物の格子の一覧項目 {
    建物の格子の一覧項目 {
        識別子: 建物定義ID::生成する(定義.識別子().綴り()).unwrap_or_else(|_| 定義の識別子が空である()),
        表示名: 定義.表示名().to_string(),
        升目の数: u32::try_from(定義.格子().升目の数()).unwrap_or(u32::MAX),
    }
}

fn 定義の識別子が空である() -> 建物定義ID {
    panic!("台帳に載った建物定義の識別子が空である。生成の検査を通った値だけが台帳に入るという不変条件に違反した")
}

fn ソースの識別子へ写す(識別子: &建物定義ID) -> Result<blitz_asset_compiler::建物定義ID, 建物の格子の保存エラー> {
    blitz_asset_compiler::建物定義ID::生成する(識別子.綴り()).map_err(建物の格子の保存エラー::ソースの形へ写せない)
}
