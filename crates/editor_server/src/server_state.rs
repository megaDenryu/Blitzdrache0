//! axumの状態として配る、編集サーバーが読み書きするパスの集まり。
//! パスの決定は起動時（`main.rs`のコンポジションルート）に閉じる。
//! 段1では静的配信ディレクトリだけを持ち、資源の永続化（`プロジェクト保管庫`）は段2で足す。
//! 参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断2」

use std::path::{Path, PathBuf};

/// サーバー状態とは、リクエストハンドラへaxumが配る、編集サーバーの依存の集まりのことである。
#[derive(Clone)]
pub struct サーバー状態 {
    静的配信ディレクトリ: PathBuf,
}

impl サーバー状態 {
    pub fn 生成する(リポジトリルート: &Path) -> Self {
        Self {
            静的配信ディレクトリ: リポジトリルート.join("editor_web/dist"),
        }
    }

    pub fn 静的配信ディレクトリ(&self) -> &Path {
        &self.静的配信ディレクトリ
    }
}
