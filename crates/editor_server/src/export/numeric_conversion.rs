//! ソース書き出しが形式境界へ渡す整数の縮小変換を担当する。

use super::error::書き出しエラー;

pub(super) fn 辺分割数へ変換する(チャンクあたり格子解像度: u32) -> Result<u16, 書き出しエラー> {
    u16::try_from(チャンクあたり格子解像度)
        .map_err(|_| 書き出しエラー::数値変換に失敗(format!("チャンクあたり格子解像度がu16へ収まらない: {チャンクあたり格子解像度}")))
}

pub(super) fn チャンク添字へ変換する(値: u32) -> Result<i32, 書き出しエラー> {
    i32::try_from(値).map_err(|_| 書き出しエラー::数値変換に失敗(format!("チャンク添字がi32へ収まらない: {値}")))
}
