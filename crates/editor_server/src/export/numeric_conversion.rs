//! ソース書き出しが形式境界へ渡す値の縮小変換を1箇所に集める。整数の幅を狭める変換も、
//! 倍精度から単精度へ狭める変換もここに置き、失敗はすべて型付きの書き出しエラーにする。

use super::error::書き出しエラー;

pub(super) fn チャンク添字へ変換する(値: u32) -> Result<i32, 書き出しエラー> {
    i32::try_from(値).map_err(|_| 書き出しエラー::数値変換に失敗(format!("チャンク添字がi32へ収まらない: {値}")))
}

/// 倍精度で持っている編集資源の値を、実行時形式が読む単精度へ狭める。無限大と非数、
/// および単精度の表現範囲を外れる値を明示の失敗にする。名前は失敗の文言へそのまま載せる。
pub(super) fn 単精度へ狭める(名前: &str, 値: f64) -> Result<f32, 書き出しエラー> {
    if !値.is_finite() || 値 < f64::from(f32::MIN) || 値 > f64::from(f32::MAX) {
        return Err(書き出しエラー::数値変換に失敗(format!("{名前}{値}がf32へ収まらない")));
    }
    値.to_string()
        .parse::<f32>()
        .ok()
        .filter(|狭めた| 狭めた.is_finite())
        .ok_or_else(|| 書き出しエラー::数値変換に失敗(format!("{名前}{値}をf32へ狭められない")))
}
