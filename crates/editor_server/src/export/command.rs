//! ソースアセット書き出しコマンド。担当するのは、保管庫が持つ大域世界とチャンクを読み、
//! blitz_asset_compilerの書式(高さ格子+チャンク目録)で`assets/<世界名>/`へ書き出す一連の手順である。
//! 「行われる操作」を構築時に依存(保管庫・出力先)を注入したコマンド型として表す
//! (グローバルCLAUDE.md「デザインパターンの既定」)。地形と建物は版付きのエディターチャンクソースを介して焼き、
//! 散布と道路のエンジン変換はしない(参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断10」)。

use blitz_asset_compiler::{高さ格子を切り出す, 高さ格子を格納する, 高さ格子諸元};
use blitz_engine::アセットID;

use super::chunk_directory_text::{ファイル名 as 目録ファイル名, 本文を組み立てる, 目録項目};
use super::chunk_edge_length;
use super::chunk_height_sample::高さ関数材料;
use super::destination::世界ソース出力先;
use super::editor_chunk_source::エディターチャンクソース;
use super::error::書き出しエラー;
use super::numeric_conversion::{チャンク添字へ変換する, 辺分割数へ変換する};
use super::result::書き出し結果;
use crate::resource::チャンク座標;
use crate::storage::{ファイル保管庫, プロジェクト保管庫};

pub struct ソースアセット書き出しコマンド {
    保管庫: ファイル保管庫,
    出力先: 世界ソース出力先,
}

impl ソースアセット書き出しコマンド {
    pub fn 生成する(保管庫: ファイル保管庫, 出力先: 世界ソース出力先) -> Self {
        Self { 保管庫, 出力先 }
    }

    pub fn 実行する(&self) -> Result<書き出し結果, 書き出しエラー> {
        let 構造 = self.保管庫.大域世界の構造を読む()?.ok_or(書き出しエラー::大域世界が未保存)?;
        let マザーバイト列 = self.保管庫.大域世界の高さ格子を読む()?.ok_or(書き出しエラー::大域世界が未保存)?;
        let 区画割り = 構造.区画割り;
        let マザー一辺頂点数 = 区画割り.マザーハイトマップの格子解像度()?;
        let 解像度 = 辺分割数へ変換する(区画割り.チャンクあたり格子解像度)?;
        let チャンク一辺メートル = chunk_edge_length::求める(区画割り.一辺のメートル, 区画割り.軸あたりチャンク数)?;
        let 諸元 = 高さ格子諸元::生成する(解像度, 1, チャンク一辺メートル)?;

        self.出力先.ディレクトリを用意する()?;
        let mut 項目一覧 = Vec::new();
        for z in 0..区画割り.軸あたりチャンク数 {
            for x in 0..区画割り.軸あたりチャンク数 {
                項目一覧.push(self.チャンクを書き出す(x, z, 諸元, 解像度, &マザーバイト列, マザー一辺頂点数)?);
            }
        }
        let 書いたチャンク数 = 項目一覧.len().saturating_mul(2);

        let 目録本文 = 本文を組み立てる(チャンク一辺メートル, &項目一覧);
        self.出力先.直下へ書き込む(目録ファイル名, 目録本文.as_bytes())?;

        Ok(書き出し結果::生成する(
            書いたチャンク数.saturating_add(1),
            self.出力先.表示の綴り(),
        ))
    }

    fn チャンクを書き出す(
        &self,
        x: u32,
        z: u32,
        諸元: 高さ格子諸元,
        解像度: u16,
        マザーバイト列: &[u8],
        マザー一辺頂点数: u32,
    ) -> Result<目録項目, 書き出しエラー> {
        let x = チャンク添字へ変換する(x)?;
        let z = チャンク添字へ変換する(z)?;
        let 座標 = チャンク座標::生成する(x, z);
        let チャンク別バイト列 = self.保管庫.チャンクの高さ格子を読む(座標)?;
        let 材料 = 高さ関数材料 {
            チャンクx: x,
            チャンクz: z,
            解像度,
            マザー一辺頂点数,
            マザーバイト列,
            チャンク別バイト列: チャンク別バイト列.as_deref(),
        };
        let エンジン座標 = blitz_engine::チャンク座標::生成する(x, z);
        let 格子 = 高さ格子を切り出す(諸元, エンジン座標, |添字x, 添字z| 材料.高さを求める(添字x, 添字z))?;

        let 名前 = format!("editor_terrain_x{x}_z{z}");
        let ファイル名 = format!("editor_terrain_x{x}_z{z}.heightgrid");
        self.出力先.直下へ書き込む(&ファイル名, &高さ格子を格納する(&格子))?;

        let 建物一覧 = self.保管庫.チャンクの構造を読む(座標)?.map(|構造| 構造.建物一覧).unwrap_or_default();
        let ソース = エディターチャンクソース::組み立てる(ファイル名, 建物一覧, 諸元.一辺メートル())?;
        let ソースファイル名 = format!("editor_chunk_x{x}_z{z}.json");
        self.出力先.直下へ書き込む(&ソースファイル名, &ソース.整形済みjsonを作る()?)?;

        Ok(目録項目 {
            x,
            z,
            アセットid: アセットID::生成する(&名前)?.文字列を返す().to_string(),
            相対ファイル名: ソースファイル名,
        })
    }
}
