//! ソースアセット書き出しコマンド。担当するのは、保管庫が持つ大域世界とチャンクを読み、
//! blitz_asset_compilerの書式(高さ格子+チャンク目録)で`assets/<世界名>/`へ書き出す一連の手順である。
//! 「行われる操作」を構築時に依存(保管庫・出力先・建物外形カタログ)を注入したコマンド型として表す
//! (グローバルCLAUDE.md「デザインパターンの既定」)。地形と建物と散布は版付きのエディターチャンクソースを介して焼き、
//! 道路のエンジン変換はしない(参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断10」)。
//! 散布は編集モデルが確定させた個体の一覧をそのまま写す。ポアソンディスクの計算の正本はブラウザ側にあり、
//! 編集サーバーもアセットコンパイラもその計算を持たない(参照: `_doc/計画/エディターからゲームまでの統合の作戦.md`「段F」)。

mod chunk_building_grids;
mod chunk_weight_grid;
mod chunk_write;

use blitz_asset_compiler::{建物の格子の台帳, 高さ格子諸元};

use self::chunk_write::書き出したチャンク;
use super::chunk_directory_text::{ファイル名 as 目録ファイル名, 本文を組み立てる};
use super::chunk_edge_length;
use super::destination::世界ソース出力先;
use super::error::書き出しエラー;
use super::numeric_conversion::辺分割数へ変換する;
use super::result::書き出し結果;
use crate::resource::建物外形カタログ;
use crate::storage::{ファイル保管庫, プロジェクト保管庫};

pub struct ソースアセット書き出しコマンド {
    保管庫: ファイル保管庫,
    出力先: 世界ソース出力先,
    建物外形カタログ: 建物外形カタログ,
    建物の格子の台帳: 建物の格子の台帳,
}

impl ソースアセット書き出しコマンド {
    pub fn 生成する(
        保管庫: ファイル保管庫,
        出力先: 世界ソース出力先,
        建物外形カタログ: 建物外形カタログ,
        建物の格子の台帳: 建物の格子の台帳,
    ) -> Self {
        Self {
            保管庫,
            出力先,
            建物外形カタログ,
            建物の格子の台帳,
        }
    }

    /// 保持している格子の台帳を工程へ貸す。書き出す側が台帳を持参するのではなく、このコマンドが渡す向きである。
    pub(super) fn 建物の格子の台帳(&self) -> &建物の格子の台帳 {
        &self.建物の格子の台帳
    }

    pub fn 実行する(&self) -> Result<書き出し結果, 書き出しエラー> {
        let 構造 = self.保管庫.大域世界の構造を読む()?.ok_or(書き出しエラー::大域世界が未保存)?;
        let マザーバイト列 = self.保管庫.大域世界の高さ格子を読む()?.ok_or(書き出しエラー::大域世界が未保存)?;
        let 区画割り = 構造.区画割り;
        let マザー一辺頂点数 = 区画割り.マザーハイトマップの格子解像度()?;
        let 解像度 = 辺分割数へ変換する(区画割り.チャンクあたり格子解像度)?;
        let チャンク一辺メートル = chunk_edge_length::求める(区画割り.一辺のメートル, 区画割り.軸あたりチャンク数)?;
        let 諸元 = 高さ格子諸元::生成する(解像度, 1, チャンク一辺メートル)?;

        self.出力先.ディレクトリを用意する()?;
        let mut 項目一覧 = Vec::new();
        let mut 書いたファイル数: usize = 0;
        for z in 0..区画割り.軸あたりチャンク数 {
            for x in 0..区画割り.軸あたりチャンク数 {
                let 書き出したチャンク {
                    目録項目, 書いた枚数
                } = self.チャンクを書き出す(x, z, 諸元, 解像度, &マザーバイト列, マザー一辺頂点数)?;
                書いたファイル数 = 書いたファイル数.saturating_add(書いた枚数);
                項目一覧.push(目録項目);
            }
        }

        let 目録本文 = 本文を組み立てる(チャンク一辺メートル, &項目一覧);
        self.出力先.直下へ書き込む(目録ファイル名, 目録本文.as_bytes())?;
        書いたファイル数 = 書いたファイル数.saturating_add(1);

        Ok(書き出し結果::生成する(書いたファイル数, self.出力先.表示の綴り()))
    }
}
