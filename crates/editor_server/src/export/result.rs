//! 書き出し結果: `ソースアセット書き出しコマンド::実行する`が成功したときに返す、
//! 書いたファイル数と出力先ディレクトリの値。

pub struct 書き出し結果 {
    書いたファイル数: usize,
    出力先ディレクトリ: String,
}

impl 書き出し結果 {
    pub(super) fn 生成する(書いたファイル数: usize, 出力先ディレクトリ: String) -> Self {
        Self {
            書いたファイル数,
            出力先ディレクトリ,
        }
    }

    pub fn 書いたファイル数(&self) -> usize {
        self.書いたファイル数
    }

    pub fn 出力先ディレクトリ(&self) -> &str {
        &self.出力先ディレクトリ
    }
}
