//! 一棟だけの検証世界を書き出すコマンド。建物定義を1件だけ受け取り、平らな1チャンクの中央へその建物を
//! 据えた世界のソースを書き出す。「行われる操作」を、構築時に依存(出力先・建物外形カタログ・格子の台帳)を
//! 注入したコマンド型として表す(グローバルCLAUDE.md「デザインパターンの既定」)。
//!
//! プロジェクトの世界ぜんたいを書き出す`ソースアセット書き出しコマンド`と分けるのは、材料が違うためである。
//! あちらは保管庫が持つ高さ場と塗りとチャンクの構造を読み、こちらは保管庫を1度も開かず、平らな地面と
//! 建物1件だけをその場で組む。1棟の姿を確かめるのに、世界の編集を保存しておく必要をなくすためである。

use blitz_asset_compiler::建物の格子の台帳;

use super::super::chunk_asset_file_names::チャンクの素材のファイル名;
use super::super::destination::世界ソース出力先;
use super::super::error::書き出しエラー;
use super::super::result::書き出し結果;
use super::chunk_write::チャンクと目録を書き出す;
use super::flat_ground::平らな地面;
use crate::resource::{建物外形カタログ, 建物定義ID};

pub struct 一棟だけの検証世界を書き出すコマンド {
    出力先: 世界ソース出力先,
    建物外形カタログ: 建物外形カタログ,
    建物の格子の台帳: 建物の格子の台帳,
}

impl 一棟だけの検証世界を書き出すコマンド {
    pub fn 生成する(
        出力先: 世界ソース出力先, 建物外形カタログ: 建物外形カタログ, 建物の格子の台帳: 建物の格子の台帳
    ) -> Self {
        Self {
            出力先,
            建物外形カタログ,
            建物の格子の台帳,
        }
    }

    pub fn 実行する(&self, 建物定義の識別子: &建物定義ID) -> Result<書き出し結果, 書き出しエラー> {
        let 格子ソース = self.格子ソースを台帳から引く(建物定義の識別子)?;
        let 地面 = 平らな地面::生成する()?;
        let 素材のファイル名 = チャンクの素材のファイル名::チャンクの添字から生成する(0, 0);
        self.出力先.ディレクトリを用意する()?;

        let 地面の枚数 = 地面.素材を書き出す(&self.出力先, &素材のファイル名)?;
        let チャンクの枚数 = チャンクと目録を書き出す(
            &self.出力先,
            &地面,
            &素材のファイル名,
            建物定義の識別子,
            格子ソース,
            &self.建物外形カタログ,
        )?;
        Ok(書き出し結果::生成する(
            地面の枚数.saturating_add(チャンクの枚数),
            self.出力先.表示の綴り(),
        ))
    }

    /// 台帳に載っていない建物定義を名指した実行は、宣言の規則から組む建物か、まだ保存していない建物である。
    /// どちらも格子を持たないため、既定へ倒さず名指して断る。
    fn 格子ソースを台帳から引く(
        &self,
        建物定義の識別子: &建物定義ID,
    ) -> Result<blitz_asset_compiler::建物の格子ソース, 書き出しエラー> {
        let 識別子 = blitz_asset_compiler::建物定義ID::生成する(建物定義の識別子.綴り()).map_err(書き出しエラー::建物の格子を読めない)?;
        self.建物の格子の台帳
            .格子ソースを識別子で引く(&識別子)
            .cloned()
            .ok_or_else(|| 書き出しエラー::建物の格子が台帳に無い {
                建物定義の識別子: 建物定義の識別子.綴り().to_string(),
            })
    }
}
