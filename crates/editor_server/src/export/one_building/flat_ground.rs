//! 一棟検証の世界の平らな地面。担当するのは、地面の寸法を決めることと、その地面の高さ格子と
//! 地表材質の重み格子を書き出すことである。
//!
//! 寸法をここで決めるのは、この世界がエディターの保存物を持たず、区画割りから寸法を導く材料が無いためである。
//! 一辺64メートルにするのは、部品カタログの一間(2.00メートル)を32ベイぶん並べられる広さであり、
//! 升目で組める建物はどれも中央へ余裕をもって収まるためである。高さを零にするのは、建物の姿だけを見る
//! 世界であり、地面の起伏が姿の判断を邪魔しないためである。

use blitz_asset_compiler::{
    地表材質の重み格子, 地表材質の重み格子を格納する, 地表材質の重み格子諸元, 高さ格子を切り出す, 高さ格子を格納する, 高さ格子諸元,
};

use super::super::chunk_asset_file_names::チャンクの素材のファイル名;
use super::super::destination::世界ソース出力先;
use super::super::error::書き出しエラー;

const チャンク一辺メートル: f32 = 64.0;

/// 高さ格子の刻み。一辺64メートルを64分割し、格子点の間隔をちょうど1メートルにする。
const 高さ格子の辺分割数: u16 = 64;

const 地面の高さメートル: f32 = 0.0;

/// 平らな地面とは、一棟検証の世界が持つ、起伏を一切持たない1チャンクの地面のことである。
pub(super) struct 平らな地面 {
    諸元: 高さ格子諸元,
}

impl 平らな地面 {
    pub(super) fn 生成する() -> Result<Self, 書き出しエラー> {
        Ok(Self {
            諸元: 高さ格子諸元::生成する(高さ格子の辺分割数, 1, チャンク一辺メートル)?,
        })
    }

    pub(super) fn チャンク一辺メートル(&self) -> f32 {
        self.諸元.一辺メートル()
    }

    /// 建物を据える高さ。地面が平らであるため、チャンクのどこでも同じ値である。
    pub(super) fn 高さメートル(&self) -> f32 {
        地面の高さメートル
    }

    /// 高さ格子と地表材質の重み格子を書き出し、書いた枚数を返す。
    pub(super) fn 素材を書き出す(
        &self,
        出力先: &世界ソース出力先,
        素材のファイル名: &チャンクの素材のファイル名,
    ) -> Result<usize, 書き出しエラー> {
        let 原点 = blitz_engine::チャンク座標::生成する(0, 0);
        let 格子 = 高さ格子を切り出す(self.諸元, 原点, |_, _| 地面の高さメートル)?;
        出力先.直下へ書き込む(&素材のファイル名.高さ格子(), &高さ格子を格納する(&格子))?;
        let 重み諸元 = 地表材質の重み格子諸元::生成する(self.諸元.格子点数())?;
        let 重み格子 = 地表材質の重み格子::先頭の層だけで塗り潰して生成する(重み諸元)?;
        出力先.直下へ書き込む(&素材のファイル名.地表材質の重み格子(), &地表材質の重み格子を格納する(&重み格子))?;
        Ok(2)
    }
}
