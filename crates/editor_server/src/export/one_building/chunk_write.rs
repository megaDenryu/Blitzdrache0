//! 一棟検証の世界のチャンク1件と目録を書き出す工程。受け取るのは平らな地面と建物の格子と建物外形カタログであり、
//! 返すのは書いたファイルの枚数である。
//!
//! 地面の素材を書く工程(`flat_ground`)と分けるのは、触れる材料が違うためである。あちらは高さと重みだけを見て
//! 地面を書き、こちらは建物の配置と格子を組んで版付きソースと目録を書く。

use blitz_asset_compiler::建物の格子ソース;
use blitz_engine::アセットID;

use super::super::chunk_asset_file_names::チャンクの素材のファイル名;
use super::super::chunk_directory_text::{ファイル名 as 目録ファイル名, 本文を組み立てる, 目録項目};
use super::super::destination::世界ソース出力先;
use super::super::editor_chunk_source::エディターチャンクソース;
use super::super::error::書き出しエラー;
use super::flat_ground::平らな地面;
use crate::resource::{位置3次元, 建物の配置, 建物外形カタログ, 建物定義ID};

/// 検証の世界で建物1棟に与える配置の名前。1棟しか置かないため固定でよい。
const 配置の識別子: &str = "検証の一棟";

pub(super) fn チャンクと目録を書き出す(
    出力先: &世界ソース出力先,
    地面: &平らな地面,
    素材のファイル名: &チャンクの素材のファイル名,
    建物定義の識別子: &建物定義ID,
    格子ソース: 建物の格子ソース,
    カタログ: &建物外形カタログ,
) -> Result<usize, 書き出しエラー> {
    let ソース = エディターチャンクソース::組み立てる(
        素材のファイル名.高さ格子(),
        素材のファイル名.地表材質の重み格子(),
        vec![チャンクの中央へ据える配置(建物定義の識別子.clone(), 地面.高さメートル())],
        vec![格子ソース],
        Vec::new(),
        地面.チャンク一辺メートル(),
        カタログ,
    )?;
    出力先.直下へ書き込む(&素材のファイル名.版付きチャンクソース(), &ソース.整形済みjsonを作る()?)?;
    let 目録本文 = 目録の本文を組み立てる(地面, 素材のファイル名)?;
    出力先.直下へ書き込む(目録ファイル名, 目録本文.as_bytes())?;
    Ok(2)
}

/// チャンクの中心を原点とする座標系であるため、原点がそのままチャンクの中央である。
fn チャンクの中央へ据える配置(建物定義の識別子: 建物定義ID, 地面の高さ: f32) -> 建物の配置 {
    建物の配置 {
        識別子: 配置の識別子.to_string(),
        建物定義ID: 建物定義の識別子,
        位置: 位置3次元 {
            x: 0.0,
            y: 地面の高さ.into(),
            z: 0.0,
        },
        向きラジアン: 0.0,
        基礎半径メートル: 0.0,
        なじみ半径メートル: 0.0,
    }
}

fn 目録の本文を組み立てる(
    地面: &平らな地面, 素材のファイル名: &チャンクの素材のファイル名
) -> Result<String, 書き出しエラー> {
    let 項目 = 目録項目 {
        x: 0,
        z: 0,
        アセットid: アセットID::生成する(&素材のファイル名.目録が指すアセットの名前())?
            .文字列を返す()
            .to_string(),
        相対ファイル名: 素材のファイル名.版付きチャンクソース(),
    };
    Ok(本文を組み立てる(地面.チャンク一辺メートル(), std::slice::from_ref(&項目)))
}
