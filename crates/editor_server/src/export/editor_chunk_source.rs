/// 書き出す形式版。読み手はblitz_asset_compilerの`editor_chunk/source.rs`にあり、
/// 両者の版が食い違うと焼きが必ず「形式版に対応していない」で落ちる。一致は`cargo xtask conform`の定数の組が見る。
pub(super) const エディターチャンクソースの形式版: u32 = 2;

#[derive(Serialize)]
pub(super) struct エディターチャンクソース {
    形式版: u32,
    高さ格子: String,
    地表材質の重み格子: String,
    建物配置一覧: Vec<建物配置ソース>,
}

#[derive(Serialize)]
#[allow(non_snake_case)]
struct 建物配置ソース {
    配置識別子: String,
    建物定義ID: 建物定義ID,
    チャンク原点からの東メートル: f32,
    チャンク原点からの南メートル: f32,
    向きラジアン: f32,
}

impl エディターチャンクソース {
    pub(super) fn 組み立てる(
        高さ格子: String,
        地表材質の重み格子: String,
        建物一覧: Vec<建物の配置>,
        チャンク一辺メートル: f32,
        カタログ: &建物外形カタログ,
    ) -> Result<Self, 書き出しエラー> {
        let チャンク一辺 = f64::from(チャンク一辺メートル);
        let 建物配置一覧 = 建物一覧
            .into_iter()
            .map(|建物| 建物配置ソース::エディター座標から変換する(建物, チャンク一辺, カタログ))
            .collect::<Result<Vec<_>, _>>()?;
        Ok(Self {
            形式版: エディターチャンクソースの形式版,
            高さ格子,
            地表材質の重み格子,
            建物配置一覧,
        })
    }

    pub(super) fn 整形済みjsonを作る(&self) -> Result<Vec<u8>, 書き出しエラー> {
        let mut バイト列 = serde_json::to_vec_pretty(self)?;
        バイト列.push(b'\n');
        Ok(バイト列)
    }
}

impl 建物配置ソース {
    fn エディター座標から変換する(
        建物: 建物の配置,
        チャンク一辺: f64,
        カタログ: &建物外形カタログ,
    ) -> Result<Self, 書き出しエラー> {
        let 中心座標 = エディターのチャンク中心座標::生成する(建物.位置.x, 建物.位置.z, チャンク一辺)?;
        let 実行時座標 = 中心座標.実行時のチャンク内座標へ変換する(チャンク一辺)?;
        let 定義 = カタログ
            .建物定義を取得する(&建物.建物定義ID)
            .ok_or_else(|| 書き出しエラー::建物定義が存在しない {
                建物識別子: 建物.識別子.clone(),
                建物定義の識別子: 建物.建物定義ID.to_string(),
            })?;
        実行時座標.外接箱の全角が収まることを確かめる(&定義.外接箱, 建物.向きラジアン, チャンク一辺, &建物.識別子)?;
        Ok(Self {
            配置識別子: 建物.識別子,
            建物定義ID: 建物.建物定義ID,
            チャンク原点からの東メートル: 単精度へ狭める("建物の局所東座標", 実行時座標.東メートル())?,
            チャンク原点からの南メートル: 単精度へ狭める("建物の局所南座標", 実行時座標.南メートル())?,
            向きラジアン: 単精度へ狭める("建物の向き", 建物.向きラジアン)?,
        })
    }
}
