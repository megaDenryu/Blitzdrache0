//! エディターチャンクソースが運ぶ散布の直列化の形と、エディターの個体一覧からの変換。担当するのは、
//! 個体を植生定義ごとの群へまとめること、座標系をエディターのチャンク中心から実行時のチャンク内へ写すこと、
//! 1チャンクの個体数が上限に収まることを確かめることである。
//!
//! 植生定義IDを個体ごとでなく群が1つ持つのは、焼く側が同じ定義の個体をまとめて1つのインスタンス群にするためであり、
//! 同じ綴りを個体の数だけJSONへ書かないためでもある。

use blitz_asset_compiler::植生定義ID;
use serde::Serialize;

use super::super::error::書き出しエラー;
use super::super::numeric_conversion::単精度へ狭める;
use super::coordinates::エディターのチャンク中心座標;
use crate::resource::散布の個体;

/// 初版が焼く唯一の植生定義の識別子の綴り。エディターの画面が種類を選ばず針葉樹1種に固定であるため、
/// 書き出しがこの綴りを与える。読み手はblitz_asset_compilerの植生定義の正本であり、未知の綴りは焼きが型付きで拒む。
const 初版の植生定義の識別子の綴り: &str = "conifer";

/// 1チャンクへ焼ける散布の個体の数の上限。ブラウザの編集モデルが持つ最大散布数と同じ値であり、
/// 手で書き換えた保存物や別の口から入った個体列がこの数を越えたときに、焼きへ渡す前のこの境界で止める。
pub(super) const チャンクあたりの散布の個体数の上限: usize = 1500;

/// 同じ植生定義を持つ個体をまとめた群1つ分。
#[derive(Serialize)]
#[allow(non_snake_case)]
pub(super) struct 散布の群ソース {
    植生定義ID: 植生定義ID,
    個体一覧: Vec<散布の個体ソース>,
}

/// 散布の個体1件。向き・大きさ・高さを持たないのは、焼く側が地表の面と配置識別子から導くためである。
#[derive(Serialize)]
struct 散布の個体ソース {
    配置識別子: String,
    チャンク原点からの東メートル: f32,
    チャンク原点からの南メートル: f32,
}

impl 散布の群ソース {
    /// 個体を1件も持たないチャンクは群を1つも作らない。空の群を書くと、焼く側が原型のglTFを開く先が
    /// 個体0件の群になり、素材の依存だけが増える。
    pub(super) fn エディターの個体一覧から組み立てる(
        個体一覧: Vec<散布の個体>,
        チャンク一辺: f64,
    ) -> Result<Vec<Self>, 書き出しエラー> {
        if 個体一覧.is_empty() {
            return Ok(Vec::new());
        }
        if 個体一覧.len() > チャンクあたりの散布の個体数の上限 {
            return Err(書き出しエラー::散布の個体数が上限を越えている {
                件数: 個体一覧.len(),
                上限: チャンクあたりの散布の個体数の上限,
            });
        }
        let 変換済み = 個体一覧
            .into_iter()
            .map(|個体| 散布の個体ソース::エディター座標から変換する(個体, チャンク一辺))
            .collect::<Result<Vec<_>, _>>()?;
        Ok(vec![Self {
            植生定義ID: 初版の植生定義の識別子(),
            個体一覧: 変換済み,
        }])
    }
}

/// 綴りの検査を通した初版の植生定義ID。正本に在る綴りを固定で渡すため、生成が落ちたら到達したらバグである。
fn 初版の植生定義の識別子() -> 植生定義ID {
    match 植生定義ID::生成する(初版の植生定義の識別子の綴り) {
        Ok(識別子) => 識別子,
        Err(原因) => panic!("初版の植生定義の識別子の綴りが空であるという不変条件に違反した: {原因}"),
    }
}

impl 散布の個体ソース {
    fn エディター座標から変換する(個体: 散布の個体, チャンク一辺: f64) -> Result<Self, 書き出しエラー> {
        let 中心座標 = エディターのチャンク中心座標::生成する(
            個体.チャンク中心からの東メートル,
            個体.チャンク中心からの南メートル,
            チャンク一辺,
        )?;
        let 実行時座標 = 中心座標.実行時のチャンク内座標へ変換する(チャンク一辺)?;
        Ok(Self {
            配置識別子: 個体.安定識別子,
            チャンク原点からの東メートル: 単精度へ狭める("散布の個体の局所東座標", 実行時座標.東メートル())?,
            チャンク原点からの南メートル: 単精度へ狭める("散布の個体の局所南座標", 実行時座標.南メートル())?,
        })
    }
}
