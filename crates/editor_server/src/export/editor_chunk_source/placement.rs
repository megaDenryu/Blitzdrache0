//! 版付きソースが運ぶ建物配置1件の直列化の形と、編集資源の建物の配置からの写し取り。
//! 受け取るのは建物の配置とチャンク一辺と建物外形カタログ、返すのは実行時のチャンク内座標を持つ配置のソースである。
//!
//! チャンクソースの型(親)から分けるのは、触れる材料が違うためである。親は素材のファイル名と一覧を組み、
//! こちらは座標系の変換と外接箱の収まりだけを見る。読み手側の同じ関心も`editor_chunk/source/placement.rs`が
//! 1つのファイルとして持っている。

use serde::Serialize;

use super::super::error::書き出しエラー;
use super::super::numeric_conversion::単精度へ狭める;
use super::coordinates::エディターのチャンク中心座標;
use crate::resource::{建物の配置, 建物外形カタログ, 建物定義ID};

#[derive(Serialize)]
#[allow(non_snake_case)]
pub(super) struct 建物配置ソース {
    pub(super) 配置識別子: String,
    pub(super) 建物定義ID: 建物定義ID,
    pub(super) チャンク原点からの東メートル: f32,
    pub(super) チャンク原点からの南メートル: f32,
    pub(super) 向きラジアン: f32,
}

impl 建物配置ソース {
    pub(super) fn エディター座標から変換する(
        建物: 建物の配置,
        チャンク一辺: f64,
        カタログ: &建物外形カタログ,
    ) -> Result<Self, 書き出しエラー> {
        let 中心座標 = エディターのチャンク中心座標::生成する(建物.位置.x, 建物.位置.z, チャンク一辺)?;
        let 実行時座標 = 中心座標.実行時のチャンク内座標へ変換する(チャンク一辺)?;
        let 定義 = カタログ
            .建物定義を取得する(&建物.建物定義ID)
            .ok_or_else(|| 書き出しエラー::建物定義が存在しない {
                建物識別子: 建物.識別子.clone(),
                建物定義の識別子: 建物.建物定義ID.to_string(),
            })?;
        実行時座標.外接箱の全角が収まることを確かめる(&定義.外接箱, 建物.向きラジアン, チャンク一辺, &建物.識別子)?;
        Ok(Self {
            配置識別子: 建物.識別子,
            建物定義ID: 建物.建物定義ID,
            チャンク原点からの東メートル: 単精度へ狭める("建物の局所東座標", 実行時座標.東メートル())?,
            チャンク原点からの南メートル: 単精度へ狭める("建物の局所南座標", 実行時座標.南メートル())?,
            向きラジアン: 単精度へ狭める("建物の向き", 建物.向きラジアン)?,
        })
    }
}
