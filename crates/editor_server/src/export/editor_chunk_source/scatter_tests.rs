//! 散布の個体のエディター座標からの変換と、1チャンクへ焼ける散布の個体数の上限を確かめる。
//! 建物の座標変換の検査は`tests`が持つ。

#![allow(clippy::unwrap_used)]

use super::scatter::チャンクあたりの散布の個体数の上限;
use super::*;

/// 一辺4メートルのチャンクの中心付近へ、同じ位置の個体を要求された件数だけ並べる。
/// 位置を散らさないのは、上限の判定が件数だけを見ることを確かめる検査だからである。
fn 散布の個体一覧を作る(件数: usize) -> Vec<散布の個体> {
    (0..件数)
        .map(|添字| 散布の個体 {
            安定識別子: format!("散布-{添字}"),
            チャンク中心からの東メートル: 0.5,
            チャンク中心からの南メートル: -0.5,
        })
        .collect()
}

#[test]
fn 散布の個体が1件も無ければ群を作らない() {
    let Ok(群一覧) = 散布の群ソース::エディターの個体一覧から組み立てる(Vec::new(), 4.0) else {
        panic!("空の個体一覧の変換が失敗した");
    };
    assert!(群一覧.is_empty());
}

#[test]
fn 上限ちょうどの散布の個体は1つの群へ収まる() {
    let Ok(群一覧) =
        散布の群ソース::エディターの個体一覧から組み立てる(散布の個体一覧を作る(チャンクあたりの散布の個体数の上限), 4.0)
    else {
        panic!("上限ちょうどの個体一覧の変換が失敗した");
    };
    assert_eq!(群一覧.len(), 1);
}

#[test]
fn 上限を1件越えた散布の個体は型付きエラーで拒む() {
    let 結果 =
        散布の群ソース::エディターの個体一覧から組み立てる(散布の個体一覧を作る(チャンクあたりの散布の個体数の上限 + 1), 4.0);
    assert!(matches!(結果, Err(書き出しエラー::散布の個体数が上限を越えている { .. })));
}

#[test]
fn 散布の個体もチャンク中心から北西原点へ移る() {
    let 個体 = 散布の個体 {
        安定識別子: "散布-0".to_string(),
        チャンク中心からの東メートル: 0.0,
        チャンク中心からの南メートル: 0.0,
    };
    let Ok(群一覧) = 散布の群ソース::エディターの個体一覧から組み立てる(vec![個体], 4.0) else {
        panic!("散布の個体の座標変換が失敗した");
    };
    let json = serde_json::to_string(&群一覧).unwrap_or_else(|原因| panic!("群のJSON化に失敗した: {原因}"));
    assert!(json.contains("\"チャンク原点からの東メートル\":2.0"), "変換後のJSON: {json}");
    assert!(json.contains("\"チャンク原点からの南メートル\":2.0"), "変換後のJSON: {json}");
}
