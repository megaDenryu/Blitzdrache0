//! 書き出し境界が行き来する2つの水平座標系の型。エディターが保存する`エディターのチャンク中心座標`と、
//! 実行時形式が読む`実行時のチャンク内座標`である。原点も値域も違う2つを同じ数値の組で持つと、
//! 変換し忘れも二重変換も型が通ってしまうため、別の型として持ち、値域の検査を生成の1箇所へ閉じる。
//! 参照: `_doc/計画/ユビキタス言語.md`「エディターのチャンク中心座標」

use super::super::error::書き出しエラー;
use crate::resource::建物の外接箱;

/// チャンクの中心を原点とし、各軸が`-チャンク一辺/2`から`+チャンク一辺/2`までを取る座標。
pub(super) struct エディターのチャンク中心座標 {
    東メートル: f64,
    南メートル: f64,
}

impl エディターのチャンク中心座標 {
    pub(super) fn 生成する(東メートル: f64, 南メートル: f64, チャンク一辺: f64) -> Result<Self, 書き出しエラー> {
        let 半辺 = チャンク一辺 * 0.5;
        if !値域に収まるか(東メートル, -半辺, 半辺) || !値域に収まるか(南メートル, -半辺, 半辺) {
            return Err(範囲外("エディターのチャンク中心座標", 東メートル, 南メートル));
        }
        Ok(Self {
            東メートル, 南メートル
        })
    }

    /// チャンクの北西角を原点とする座標へ、半辺だけ平行移動して写す。チャンク番号は混ぜない。
    pub(super) fn 実行時のチャンク内座標へ変換する(
        self,
        チャンク一辺: f64,
    ) -> Result<実行時のチャンク内座標, 書き出しエラー> {
        let 半辺 = チャンク一辺 * 0.5;
        実行時のチャンク内座標::生成する(self.東メートル + 半辺, self.南メートル + 半辺, チャンク一辺)
    }
}

/// チャンクの北西角を原点とし、各軸が0からチャンク一辺までを取る座標。南メートルは北の辺からの距離である。
pub(super) struct 実行時のチャンク内座標 {
    東メートル: f64,
    南メートル: f64,
}

impl 実行時のチャンク内座標 {
    fn 生成する(東メートル: f64, 南メートル: f64, チャンク一辺: f64) -> Result<Self, 書き出しエラー> {
        if !値域に収まるか(東メートル, 0.0, チャンク一辺) || !値域に収まるか(南メートル, 0.0, チャンク一辺) {
            return Err(範囲外("実行時のチャンク内座標", 東メートル, 南メートル));
        }
        Ok(Self {
            東メートル, 南メートル
        })
    }

    pub(super) fn 東メートル(&self) -> f64 {
        self.東メートル
    }

    pub(super) fn 南メートル(&self) -> f64 {
        self.南メートル
    }

    /// 建物の外接箱を配置の向きで回した4つの角が、すべて所有チャンクの内側へ収まることを確かめる。
    /// 根の1点だけを見ると、境界近くへ据えた建物の壁や屋根が隣のチャンクへはみ出したまま通る。
    pub(super) fn 外接箱の全角が収まることを確かめる(
        &self,
        箱: &建物の外接箱,
        向きラジアン: f64,
        チャンク一辺: f64,
        建物識別子: &str,
    ) -> Result<(), 書き出しエラー> {
        let 正弦 = 向きラジアン.sin();
        let 余弦 = 向きラジアン.cos();
        for x in [f64::from(箱.最小[0]), f64::from(箱.最大[0])] {
            for z in [f64::from(箱.最小[2]), f64::from(箱.最大[2])] {
                let 東 = self.東メートル + 余弦 * x + 正弦 * z;
                let 南 = self.南メートル - 正弦 * x + 余弦 * z;
                if !値域に収まるか(東, 0.0, チャンク一辺) || !値域に収まるか(南, 0.0, チャンク一辺) {
                    return Err(書き出しエラー::建物が所有チャンクの外にある {
                        建物識別子: 建物識別子.to_string(),
                        局所の東: 東,
                        局所の南: 南,
                        チャンク一辺,
                    });
                }
            }
        }
        Ok(())
    }
}

fn 値域に収まるか(値: f64, 下限: f64, 上限: f64) -> bool {
    値.is_finite() && (下限..=上限).contains(&値)
}

fn 範囲外(座標系の呼び名: &str, 東メートル: f64, 南メートル: f64) -> 書き出しエラー {
    書き出しエラー::数値変換に失敗(format!("{座標系の呼び名}(東{東メートル}・南{南メートル})が有効範囲外である"))
}
