//! エディターのチャンク中心座標から実行時の南西原点座標への変換規約を確かめる。

use super::*;
use crate::resource::位置3次元;

fn 建物を作る(x: f64, z: f64) -> 建物の配置 {
    建物の配置 {
        識別子: "stable-building".to_string(),
        建物定義ID: "frame_house_one_bay".to_string(),
        位置: 位置3次元 { x, y: 999.0, z },
        向きラジアン: 0.25,
        基礎半径メートル: 4.0,
        なじみ半径メートル: 8.0,
    }
}

#[test]
fn チャンク中心は南西原点から半辺の位置へ移る() {
    let Ok(変換後) = 建物配置ソース::エディター座標から変換する(建物を作る(0.0, 0.0), -2.0, -2.0, 4.0) else {
        panic!("チャンク中心の座標変換が失敗した");
    };
    assert_eq!(変換後.チャンク原点からの東メートル, 2.0);
    assert_eq!(変換後.チャンク原点からの南メートル, 2.0);
}

#[test]
fn チャンク中心から半辺を越えた位置を拒む() {
    let 結果 = 建物配置ソース::エディター座標から変換する(建物を作る(2.1, 0.0), -2.0, -2.0, 4.0);
    assert!(matches!(結果, Err(書き出しエラー::建物が所有チャンクの外にある { .. })));
}
