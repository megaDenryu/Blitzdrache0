//! 建物のエディターのチャンク中心座標から実行時の北西原点座標への変換規約を確かめる。
//! 散布の個体の変換と個体数の上限は`scatter_tests`が持つ。

use super::placement::建物配置ソース;
use super::*;
use crate::resource::建物定義ID;
use crate::resource::{
    ベイ構造, 位置3次元, 建物の入口方向, 建物の外接箱, 建物外形カタログ, 建物外形定義, 建物定義の用途
};

const 家屋の識別子: &str = "frame_house_one_bay";

fn 建物定義の識別子を作る() -> 建物定義ID {
    match 建物定義ID::生成する(家屋の識別子) {
        Ok(識別子) => 識別子,
        Err(原因) => panic!("試験に使う建物定義の識別子を作れない: {原因}"),
    }
}

fn 建物を作る(x: f64, z: f64) -> 建物の配置 {
    建物の配置 {
        識別子: "stable-building".to_string(),
        建物定義ID: 建物定義の識別子を作る(),
        位置: 位置3次元 { x, y: 999.0, z },
        向きラジアン: 0.25,
        基礎半径メートル: 4.0,
        なじみ半径メートル: 8.0,
    }
}

fn カタログを作る() -> 建物外形カタログ {
    建物外形カタログ {
        形式版: crate::resource::建物外形カタログの現在の形式版,
        建物定義一覧: vec![建物外形定義 {
            識別子: 建物定義の識別子を作る(),
            表示名: "家".to_string(),
            用途: 建物定義の用途::家屋,
            部品の識別子一覧: vec!["part".to_string()],
            ベイ: ベイ構造 { 横: 1, 奥: 1, 階: 1 },
            入口のローカル方向: 建物の入口方向 { x: 0.0, z: 1.0 },
            外接箱: 建物の外接箱 {
                最小: [-0.25, 0.0, -0.25],
                最大: [0.25, 1.0, 0.25],
            },
        }],
    }
}

#[test]
fn チャンク中心は北西原点から半辺の位置へ移る() {
    let Ok(変換後) = 建物配置ソース::エディター座標から変換する(建物を作る(0.0, 0.0), 4.0, &カタログを作る())
    else {
        panic!("チャンク中心の座標変換が失敗した");
    };
    assert_eq!(変換後.チャンク原点からの東メートル, 2.0);
    assert_eq!(変換後.チャンク原点からの南メートル, 2.0);
}

#[test]
fn チャンク中心から半辺を越えた位置を拒む() {
    let 結果 = 建物配置ソース::エディター座標から変換する(建物を作る(2.1, 0.0), 4.0, &カタログを作る());
    assert!(結果.is_err());
}

#[test]
fn 建物の根が内側でも回転後の外接箱の角が越境すれば拒む() {
    let 結果 = 建物配置ソース::エディター座標から変換する(建物を作る(1.9, 0.0), 4.0, &カタログを作る());
    assert!(matches!(結果, Err(書き出しエラー::建物が所有チャンクの外にある { .. })));
}

#[test]
fn カタログに無い建物定義を指す配置は変換を拒む() {
    let カタログ = 建物外形カタログ {
        形式版: crate::resource::建物外形カタログの現在の形式版,
        建物定義一覧: Vec::new(),
    };
    let 結果 = 建物配置ソース::エディター座標から変換する(建物を作る(0.0, 0.0), 4.0, &カタログ);
    assert!(matches!(結果, Err(書き出しエラー::建物定義が存在しない { .. })));
}
