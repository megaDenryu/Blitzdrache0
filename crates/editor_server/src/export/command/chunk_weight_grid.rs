//! チャンク1件ぶんの地表材質の重み格子を組む工程。受け取るのはチャンクの座標と一辺の標本数であり、
//! 返すのはソース形式へ格納できる重みの格子である。
//!
//! まだ一度も塗られていないチャンクにも格子を組むのは、書き出したソースの形式版2が重みの欄を必須に
//! するためである。欄の不在で「無し」を表すと、読み手が欄の有無で経路を分けることになる。

use blitz_asset_compiler::{地表材質の重み格子, 地表材質の重み格子諸元};

use super::super::error::書き出しエラー;
use super::ソースアセット書き出しコマンド;
use crate::resource::チャンク座標;
use crate::storage::プロジェクト保管庫;

impl ソースアセット書き出しコマンド {
    pub(super) fn チャンクの地表材質の重み格子を組む(
        &self,
        座標: チャンク座標,
        一辺の標本数: u32,
    ) -> Result<地表材質の重み格子, 書き出しエラー> {
        let 諸元 = 地表材質の重み格子諸元::生成する(一辺の標本数)?;
        match self.保管庫.チャンクの材質重みを読む(座標)? {
            Some(バイト列) => Ok(地表材質の重み格子::生成する(諸元, バイト列)?),
            None => Ok(地表材質の重み格子::先頭の層だけで塗り潰して生成する(諸元)?),
        }
    }
}
