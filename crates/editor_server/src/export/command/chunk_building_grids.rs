//! チャンク1件が使う建物の格子を集める工程。受け取るのはそのチャンクの建物配置一覧、返すのは
//! 格子から組む建物のソースを識別子の重複なく並べたものである。
//!
//! 置き場に格子ファイルを持つ建物定義だけを格子由来として扱う。持たない建物定義は宣言の規則から組む建物であり、
//! 焼く側が正本の5件から引く。判定を置き場の実在に置くのは、由来の写しを別の欄で持つと、
//! 格子を消したのに欄が残った保存物が「格子から組むはずの建物が見つからない」で落ちるためである。

use blitz_asset_compiler::建物の格子ソース;

use super::super::error::書き出しエラー;
use crate::resource::建物の配置;

impl super::ソースアセット書き出しコマンド {
    pub(super) fn チャンクが使う建物の格子を集める(
        &self,
        建物一覧: &[建物の配置],
    ) -> Result<Vec<建物の格子ソース>, 書き出しエラー> {
        let mut 一覧: Vec<建物の格子ソース> = Vec::new();
        for 建物 in 建物一覧 {
            if 一覧.iter().any(|格子| 格子.建物定義ID.綴り() == 建物.建物定義ID.綴り()) {
                continue;
            }
            let 識別子 = blitz_asset_compiler::建物定義ID::生成する(建物.建物定義ID.綴り()).map_err(書き出しエラー::建物の格子を読めない)?;
            let ファイル = self.建物の格子の置き場().建物定義の格子ファイル(&識別子);
            if !ファイル.パス().is_file() {
                continue;
            }
            一覧.push(
                ファイル
                    .読んで最新の形にする()
                    .map_err(|原因| 書き出しエラー::建物の格子を読めない(原因.to_string()))?,
            );
        }
        Ok(一覧)
    }
}
