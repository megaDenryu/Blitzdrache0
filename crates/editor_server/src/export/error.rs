//! ソースアセット書き出しの型付きエラー。担当するのは、書き出しコマンドが失敗しうる理由を
//! 1つの語彙へ集めることだけである。ルート側の`response`がこれをHTTP応答へ変換する。

/// 書き出しエラーとは、`ソースアセット書き出しコマンド::実行する`が返しうる失敗の区別のことである。
#[derive(thiserror::Error, Debug)]
pub enum 書き出しエラー {
    #[error("出力先の世界名が不正である: {0}")]
    世界名が不正(String),

    #[error("大域世界の構造または高さ格子がまだ保存されていない。先に大域世界を保存する")]
    大域世界が未保存,

    #[error("区画割りからの寸法の導出に失敗した: {0}")]
    区画割りの導出に失敗(#[from] crate::resource::資源検証エラー),

    #[error("高さ格子の諸元または切り出しの計算に失敗した: {0}")]
    高さ格子処理に失敗(#[from] blitz_asset_compiler::高さ格子エラー),

    #[error("地表材質の重み格子の諸元または組み立てに失敗した: {0}")]
    地表材質の重み格子処理に失敗(#[from] blitz_asset_compiler::地表材質の重み格子エラー),

    #[error("アセットIDの生成に失敗した: {0}")]
    アセットIDが不正(#[from] blitz_engine::アセットIDエラー),

    #[error("数値の変換に失敗した: {0}")]
    数値変換に失敗(String),

    #[error("建物{建物識別子}の局所位置({局所の東}, {局所の南})が一辺{チャンク一辺}mの所有チャンク外にある")]
    建物が所有チャンクの外にある {
        建物識別子: String,
        局所の東: f64,
        局所の南: f64,
        チャンク一辺: f64,
    },

    #[error("建物{建物識別子}が参照する建物定義の識別子{建物定義の識別子}はカタログに存在しない")]
    建物定義が存在しない {
        建物識別子: String, 建物定義の識別子: String
    },

    #[error("1チャンクの散布の個体が{件数}件あり、上限{上限}件を越えている")]
    散布の個体数が上限を越えている { 件数: usize, 上限: usize },

    #[error("保管庫の読み込みに失敗した: {0}")]
    読み込みに失敗(#[from] crate::storage::読み込みエラー),

    #[error("出力先ファイルへの書き込みに失敗した: {0}")]
    書き込みに失敗(#[from] std::io::Error),

    #[error("建物の格子を読めない: {0}")]
    建物の格子を読めない(String),

    #[error("建物定義{建物定義の識別子}の格子が台帳に無い。建物エディターで保存してから焼く")]
    建物の格子が台帳に無い { 建物定義の識別子: String },

    #[error("版付きチャンクソースのJSONを組み立てられない: {0}")]
    JSON組み立てに失敗(#[from] serde_json::Error),
}
