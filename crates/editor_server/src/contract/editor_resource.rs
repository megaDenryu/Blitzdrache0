//! `編集資源契約.ts`の本文。型宣言の並びを道具ごとの2つのモジュールから束ね、値として出す定数を足す。
//!
//! 形式版と既定のコード進行を値として出すのは、ブラウザが同じ定数の写しを持たなくて済むようにするためである。
//! 写しを持つと、片方だけが変わった食い違いが実行するまで出ない
//! (参照: `_doc/設計/楽曲エディター.md`「判断9」「判断10」)。

mod music_types;
mod world_editing_types;

use ts_rs::Config;

pub fn 編集資源契約の本文を組み立てる() -> String {
    let 設定 = Config::new();
    let mut 型宣言一覧 = world_editing_types::大域とチャンクの編集の型宣言の並び(&設定).to_vec();
    型宣言一覧.extend(music_types::楽曲の型宣言の並び(&設定));
    let mut 本文 = super::本文を組み立てる(&型宣言一覧);
    本文.push_str(&format!(
        "export const 建物外形カタログ形式版 = {} as const;\n",
        crate::建物外形カタログの現在の形式版
    ));
    本文.push_str(&format!(
        "export const 建物の格子の形式版 = {} as const;\n",
        crate::建物の格子の現在の形式版
    ));
    本文.push_str(&format!("export const 楽曲の形式版 = {} as const;\n", crate::楽曲の現在の形式版));
    本文.push_str(&format!(
        "export const 既定のコード進行一覧: 既定のコード進行[] = {};\n",
        既定のコード進行一覧のjson()
    ));
    本文.push_str(&値の範囲の定数());
    本文
}

/// 検証が引いている範囲の定数をそのまま値として出す。ブラウザが同じ数を書き写すと3つ目の写しになるためである。
/// 正本は`resource/music/value_range.rs`の1箇所だけであり、ここは並べ替えずに写す。
fn 値の範囲の定数() -> String {
    [
        定数の行("小節あたりのステップ数", crate::小節あたりのステップ数),
        定数の行("新しいパターンの既定の小節数", crate::新しいパターンの既定の小節数),
        定数の行("パターンの小節数の上限", crate::パターンの小節数の上限),
        定数の行("テンポの下限", crate::テンポの下限),
        定数の行("テンポの上限", crate::テンポの上限),
        定数の行("曲の節の繰り返し回数の下限", crate::曲の節の繰り返し回数の下限),
        定数の行("曲の節の繰り返し回数の上限", crate::曲の節の繰り返し回数の上限),
        定数の行("音高番号の下限", crate::音高番号の下限),
        定数の行("音高番号の上限", crate::音高番号の上限),
        定数の行("和音の根音の下限", crate::和音の根音の下限),
        定数の行("和音の根音の上限", crate::和音の根音の上限),
        定数の行("和音の続くステップ数の下限", crate::和音の続くステップ数の下限),
        定数の行("和音の続くステップ数の上限", crate::和音の続くステップ数の上限),
        定数の行("音量と効果の比の下限", crate::音量と効果の比の下限),
        定数の行("音量と効果の比の上限", crate::音量と効果の比の上限),
        定数の行("遅延のステップ数の下限", crate::遅延のステップ数の下限),
        定数の行("遅延のステップ数の上限", crate::遅延のステップ数の上限),
    ]
    .concat()
}

fn 定数の行(名前: &str, 値: impl std::fmt::Display) -> String {
    format!("export const {名前} = {値} as const;\n")
}

/// 進行1件を1行へ畳むのは、生成物の差分が進行の単位で出るようにするためである。
fn 既定のコード進行一覧のjson() -> String {
    let 行一覧: Vec<String> = crate::既定のコード進行一覧().iter().map(進行1件のjson).collect();
    format!("[\n  {}\n]", 行一覧.join(",\n  "))
}

/// 直列化できない欄を1つも持たない型のため、失敗したら型契約の組み立ての不変条件が破れている。
fn 進行1件のjson(進行: &crate::既定のコード進行) -> String {
    serde_json::to_string(進行)
        .unwrap_or_else(|誤り| panic!("既定のコード進行を値として書き出せない。全ての欄がJSONへ写せるという不変条件に違反した: {誤り}"))
}
