//! 編集サーバーのエントリポイント。コンポジションルート:
//! リポジトリルートの解決 → サーバー状態の生成 → ルーターの組み立て → 待受。
//! `127.0.0.1`だけへ結び付け、外部からの接続を受けない。

use editor_server::{
    サーバー状態, プロジェクトルートを解決する, リポジトリルートを解決する, ルーターを組み立てる
};

#[tokio::main]
async fn main() {
    let リポジトリルート = リポジトリルートを解決する();
    let 引数一覧: Vec<String> = std::env::args().collect();
    let プロジェクトルート = プロジェクトルートを解決する(&引数一覧, &リポジトリルート);
    let 状態 = サーバー状態::生成する(&リポジトリルート, &プロジェクトルート);
    let ルーター = ルーターを組み立てる(状態);

    let アドレス = std::net::SocketAddr::from(([127, 0, 0, 1], 7901));
    match tokio::net::TcpListener::bind(アドレス).await {
        Ok(リスナー) => {
            println!("編集サーバーを起動した: http://{アドレス}");
            if let Err(原因) = axum::serve(リスナー, ルーター).await {
                eprintln!("編集サーバーが異常終了した: {原因}");
            }
        }
        Err(原因) => {
            eprintln!("ポート{}への待受に失敗した: {原因}", アドレス.port());
        }
    }
}
