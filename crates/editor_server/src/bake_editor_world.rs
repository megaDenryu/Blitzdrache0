//! 編集サーバーがエディターの世界を実行時形式へ焼く局面。担当するのは、焼く直前にマテリアル台帳から
//! 地表材質の層割当を読み、焼く世界の指定を組んでコンパイルを回すことである。
//!
//! 層割当を焼くたびに読み直すのは、台帳の編集が次の保存で絵へ届くためである。起動時に1度だけ読むと、
//! 層の割り当てを変えても焼き直しに反映されない。
//! 台帳がまだ1度も保存されていない場合に既定の割当を使うのは、初回起動のプロジェクトが台帳を持たないためであり、
//! 台帳がある場合に既定へ落ちる経路は無い(読めない台帳は型付きの失敗になる)。

use blitz_asset_compiler::{地表材質の層割当, 実行時アセットのコンパイルエラー};

use crate::server_state::サーバー状態;
use crate::storage::プロジェクト保管庫;

impl サーバー状態 {
    pub(crate) fn エディターの世界をベイクする(&self) -> Result<(), 実行時アセットのコンパイルエラー> {
        let 層割当 = self.地表材質の層割当を読む()?;
        let 指定 = blitz_asset_compiler::焼く世界の指定::エディターの世界を焼く(
            self.リポジトリルート().ソースルート(),
            self.リポジトリルート().エディター実行時形式の出力先(),
            層割当,
        );
        blitz_asset_compiler::実行時アセットのコンパイル::始める(指定)?.世界を焼く()
    }

    fn 地表材質の層割当を読む(&self) -> Result<地表材質の層割当, 実行時アセットのコンパイルエラー> {
        let 読み取り結果 = self
            .保管庫()
            .マテリアル台帳を読む()
            .map_err(|原因| 実行時アセットのコンパイルエラー::ソース不正(format!("マテリアル台帳を読めない: {原因}")))?;
        let Some(台帳) = 読み取り結果 else {
            return Ok(地表材質の層割当::既定を作る());
        };
        let 層ごとの材質名 = 台帳.層割当.参照する材質名一覧().map(str::to_string);
        地表材質の層割当::生成する(層ごとの材質名)
            .map_err(|原因| 実行時アセットのコンパイルエラー::ソース不正(format!("マテリアル台帳の層割当が不正である: {原因}")))
    }
}
