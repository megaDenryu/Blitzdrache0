//! 編集資源の検証エラー。数値・識別子・格子寸法の検証はすべてこの1つの型に集約する。
//! 検証の主体は各資源型の`検証する()`メソッドであり、この型は失敗理由を運ぶだけである。

/// 資源検証エラーとは、編集資源の型が自身の`検証する()`で見つけた不変条件違反のことである。
#[derive(thiserror::Error, Debug, Clone, PartialEq)]
pub enum 資源検証エラー {
    #[error("{フィールド名}は有限の正の数でなければならないが{値}だった")]
    正の有限数でない { フィールド名: &'static str, 値: f64 },

    #[error("{フィールド名}は有限の数でなければならないが{値}だった")]
    有限数でない { フィールド名: &'static str, 値: f64 },

    #[error("{フィールド名}は1以上でなければならないが{値}だった")]
    最小件数を下回る { フィールド名: &'static str, 値: u32 },

    #[error("識別子が空である")]
    識別子が空,

    #[error("なじみ半径メートル({なじみ半径}m)が基礎半径メートル({基礎半径}m)を下回っている")]
    なじみ半径が基礎半径を下回る { 基礎半径: f64, なじみ半径: f64 },

    #[error("格子のバイト長が寸法と整合しない: 一辺の頂点数{一辺の頂点数}に対し期待{期待バイト長}バイトだが実際は{実際バイト長}バイトだった")]
    格子のバイト長が不整合 {
        一辺の頂点数: u32,
        期待バイト長: u64,
        実際バイト長: u64,
    },

    #[error("数値の変換に失敗した: {説明}")]
    数値変換に失敗 { 説明: String },

    #[error("{フィールド名}は#+16進6桁の書式でなければならないが\"{値}\"だった")]
    色書式が不正 { フィールド名: &'static str, 値: String },

    #[error("{フィールド名}に同じ名前が重複している: \"{値}\"")]
    名前が重複している { フィールド名: &'static str, 値: String },

    #[error("{フィールド名}が参照している\"{値}\"は一覧に存在しない")]
    参照先が存在しない { フィールド名: &'static str, 値: String },

    #[error("{フィールド名}は{最小}以上{最大}以下の整数でなければならないが{値}だった")]
    整数が範囲外 {
        フィールド名: &'static str,
        値: i64,
        最小: i64,
        最大: i64,
    },

    #[error("{フィールド名}は{最小}以上{最大}以下でなければならないが{値}だった")]
    小数が範囲外 {
        フィールド名: &'static str,
        値: f64,
        最小: f64,
        最大: f64,
    },

    #[error("{フィールド名}の件数は{期待件数}でなければならないが{実際件数}だった")]
    件数が期待と違う {
        フィールド名: &'static str,
        期待件数: usize,
        実際件数: usize,
    },

    #[error("{フィールド名}の組み合わせが成り立たない: {説明}")]
    組み合わせが成り立たない { フィールド名: &'static str, 説明: String },

    #[error("識別子\"{値}\"にファイル名として使えない文字{文字:?}がある")]
    識別子にファイル名として使えない文字がある { 値: String, 文字: char },
}
