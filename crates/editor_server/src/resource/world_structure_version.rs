//! 保存済みの大域世界構造を、版ごとの型で受け取って最新の形へ変換する。
//! 1つの型へ互換用の細工を足し続けず、旧版は旧版の型として丸ごと持つ
//! (参照: グローバルCLAUDE.md「シリアライズデータの後方互換は『版ごとの型＋最新への変換』で表す」)。
//! 変換の向きは常に旧版から最新へ一方通行であり、保存は最新の形だけで行う。

use serde::Deserialize;

use super::regional_road::広域道路;
use super::world_layout::世界の区画割り;
use super::world_structure::大域世界構造;

/// 広域道路を1本だけ持つ旧版の大域世界構造とは、大域世界に幹線が1本しか置けなかった頃の
/// `大域世界/構造`のJSONの形のことである。
#[derive(Debug, Clone, PartialEq, Deserialize)]
pub struct 広域道路を1本だけ持つ旧版の大域世界構造 {
    pub 区画割り: 世界の区画割り,
    pub 広域道路: 広域道路,
}

impl 広域道路を1本だけ持つ旧版の大域世界構造 {
    pub fn 最新の形へ変換する(self) -> 大域世界構造 {
        大域世界構造 {
            区画割り: self.区画割り,
            広域道路一覧: vec![self.広域道路],
        }
    }
}

/// 読み込んだ大域世界構造の版とは、保存されているJSONがどの版の形で書かれていたかを表す判別のことである。
/// JSONに版番号の欄は無いため、最新の形から順に当てはめ、当てはまった形をその版と決める。
#[derive(Debug, Clone, PartialEq, Deserialize)]
#[serde(untagged)]
pub enum 読み込んだ大域世界構造の版 {
    最新(大域世界構造),
    広域道路が1本だけの旧版(広域道路を1本だけ持つ旧版の大域世界構造),
}

impl 読み込んだ大域世界構造の版 {
    pub fn 最新の形へ変換する(self) -> 大域世界構造 {
        match self {
            Self::最新(構造) => 構造,
            Self::広域道路が1本だけの旧版(構造) => 構造.最新の形へ変換する(),
        }
    }
}
