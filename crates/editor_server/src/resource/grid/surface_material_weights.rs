//! 地表材質の重みの型契約。チャンクのバイナリ資源であり、草・泥・岩・砂の4層をu8の
//! RGBA配列(R=草・G=泥・B=岩・A=砂)として持つ。重みの合計を255へ正規化する責務は
//! TS側の編集モデルが持ち、ここでは長さ検証のみを行う。
//! `GET|PUT /api/チャンク/{x}/{z}/材質重み`でoctet-streamとして読み書きする。

use super::square_byte_grid::正方形バイト格子;
use crate::resource::validation_error::資源検証エラー;

const 層数: u32 = 4;

/// 地表材質の重みとは、1チャンクの地表を草・泥・岩・砂の4層でどう塗り分けたかを持つ、
/// 頂点ごとu8×4チャンネルの格子のことである。
pub struct 地表材質の重み(正方形バイト格子);

impl 地表材質の重み {
    pub fn 生成する(一辺の頂点数: u32, バイト列: Vec<u8>) -> Result<Self, 資源検証エラー> {
        正方形バイト格子::生成する(一辺の頂点数, 層数, バイト列).map(Self)
    }

    pub fn 一辺の頂点数(&self) -> u32 {
        self.0.一辺の頂点数()
    }

    pub fn バイト列(&self) -> &[u8] {
        self.0.バイト列()
    }

    pub fn バイト列を取り出す(self) -> Vec<u8> {
        self.0.バイト列を取り出す()
    }
}
