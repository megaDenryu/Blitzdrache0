//! 正方形の格子(高さ格子・材質重み格子)が共通で使う、寸法とバイト長の整合検証。
//! 依存も副作用も持たない純粋関数のため自由関数として置く(CLAUDE.md「自由関数の許容2条件」(a))。

use crate::resource::validation_error::資源検証エラー;

/// 一辺の頂点数と1頂点あたりのバイト数から期待するバイト長を求め、実際のバイト列長と比較する。
/// 桁あふれの余地を無くすため`u64`で計算する(現実的などの寸法でもu64の範囲へ収まる)。
pub(super) fn バイト長を検証する(
    一辺の頂点数: u32, 一頂点あたりバイト数: u32, 実際のバイト列: &[u8]
) -> Result<(), 資源検証エラー> {
    let 一辺の頂点数64 = u64::from(一辺の頂点数);
    let 一頂点あたりバイト数64 = u64::from(一頂点あたりバイト数);
    let 期待バイト長 = 一辺の頂点数64
        .checked_mul(一辺の頂点数64)
        .and_then(|頂点総数| 頂点総数.checked_mul(一頂点あたりバイト数64))
        .ok_or_else(|| 資源検証エラー::数値変換に失敗 {
            説明: "格子の期待バイト長の計算が桁あふれした".to_string(),
        })?;
    let 実際バイト長 = u64::try_from(実際のバイト列.len()).map_err(|原因| 資源検証エラー::数値変換に失敗 {
        説明: format!("バイト列長をu64へ変換できない: {原因}"),
    })?;
    if 期待バイト長 == 実際バイト長 {
        Ok(())
    } else {
        Err(資源検証エラー::格子のバイト長が不整合 {
            一辺の頂点数,
            期待バイト長,
            実際バイト長,
        })
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn 期待どおりのバイト長は受理する() {
        assert!(バイト長を検証する(3, 4, &[0u8; 36]).is_ok());
    }

    #[test]
    fn バイト長が違えば拒否する() {
        assert!(バイト長を検証する(3, 4, &[0u8; 35]).is_err());
    }
}
