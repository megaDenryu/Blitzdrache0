//! チャンクの高さ編集の型契約。チャンクのバイナリ資源であり、f32のリトルエンディアン列を
//! 行優先で持つ。構造化データ(チャンク構造)には含めず、
//! `GET|PUT /api/チャンク/{x}/{z}/高さ格子`でoctet-streamとして別口に読み書きする。
//! 1辺の頂点数は`世界の区画割り::チャンク格子の頂点数()`が導く値と、経路の側で突き合わせる。

use super::square_byte_grid::正方形バイト格子;
use crate::resource::validation_error::資源検証エラー;

const 一頂点あたりバイト数: u32 = 4;

/// チャンクの高さ編集とは、1チャンク単独で編集する高さ場のf32格子のことである。
pub struct チャンクの高さ編集(正方形バイト格子);

impl チャンクの高さ編集 {
    pub fn 生成する(一辺の頂点数: u32, バイト列: Vec<u8>) -> Result<Self, 資源検証エラー> {
        正方形バイト格子::生成する(一辺の頂点数, 一頂点あたりバイト数, バイト列).map(Self)
    }

    pub fn 一辺の頂点数(&self) -> u32 {
        self.0.一辺の頂点数()
    }

    pub fn バイト列(&self) -> &[u8] {
        self.0.バイト列()
    }

    pub fn バイト列を取り出す(self) -> Vec<u8> {
        self.0.バイト列を取り出す()
    }
}
