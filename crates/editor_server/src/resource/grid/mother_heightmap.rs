//! マザーハイトマップの型契約。大域世界のバイナリ資源であり、f32のリトルエンディアン列を
//! 行優先(横→縦)で持つ。構造化データ(大域世界構造)には含めず、
//! `GET|PUT /api/大域世界/高さ格子`でoctet-streamとして別口に読み書きする。

use super::square_byte_grid::正方形バイト格子;
use crate::resource::validation_error::資源検証エラー;

const 一頂点あたりバイト数: u32 = 4;

/// マザーハイトマップとは、大域世界全体を1枚の連続したf32格子として持つ高さ場のことである。
/// 境界での不連続が原理的に起きないよう、チャンクへ分ける前の連続バッファとして保持する。
pub struct マザーハイトマップ(正方形バイト格子);

impl マザーハイトマップ {
    pub fn 生成する(一辺の頂点数: u32, バイト列: Vec<u8>) -> Result<Self, 資源検証エラー> {
        正方形バイト格子::生成する(一辺の頂点数, 一頂点あたりバイト数, バイト列).map(Self)
    }

    pub fn 一辺の頂点数(&self) -> u32 {
        self.0.一辺の頂点数()
    }

    pub fn バイト列(&self) -> &[u8] {
        self.0.バイト列()
    }

    pub fn バイト列を取り出す(self) -> Vec<u8> {
        self.0.バイト列を取り出す()
    }
}
