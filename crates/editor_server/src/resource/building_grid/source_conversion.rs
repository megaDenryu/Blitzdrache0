//! 型契約の建物の格子を、アセットコンパイラが読むソースの形へ写す工程。受け取るのは型契約の値、
//! 返すのは同じ内容のソースの値である。
//!
//! 写しを機械に書かせず1本の関数で書くのは、欄が対応していることをコンパイラに確かめさせるためである。
//! 型契約の側に欄を足してソースの側へ足し忘れると、この写しが組み立てられずビルドが止まる。
//!
//! 逆向きの写し(ソースから型契約へ)を持たないのは、編集サーバーが格子の正本の書き手だからである。
//! 読みはソースのファイルをそのままJSONとして返せば足り、型を経由する必要がない。

use blitz_asset_compiler::{
    はめ口ソース, 升目の屋根ソース, 升目の床ソース, 升目の座標ソース, 升目の複体ソース, 升目ソース, 壁の外面の飾りソース, 壁の種類ソース,
    建物の入口方向ソース, 建物の格子ソース, 建物の装飾ソース,
};

use super::cell::{升目の宣言, 升目の屋根, 升目の床, 升目の座標};
use super::opening::{はめ口の値, 壁の外面の飾り, 壁の種類};
use super::建物の格子;

impl 建物の格子 {
    /// アセットコンパイラが読むソースの形へ写す。建物定義IDの綴りは検査済みであり、写しで作り直しても落ちない。
    pub(crate) fn ソースの形へ写す(&self) -> Result<建物の格子ソース, String> {
        Ok(建物の格子ソース {
            形式版: self.形式版,
            建物定義ID: blitz_asset_compiler::建物定義ID::生成する(self.建物定義ID.綴り())?,
            表示名: self.表示名.clone(),
            入口のローカル方向: 建物の入口方向ソース {
                x: self.入口のローカル方向.x,
                z: self.入口のローカル方向.z,
            },
            格子: 升目の複体ソース {
                根の升目: 座標を写す(self.格子.根の升目),
                升目一覧: self.格子.升目一覧.iter().map(|升目| 升目を写す(*升目)).collect(),
            },
            装飾: 建物の装飾ソース {},
        })
    }
}

fn 座標を写す(座標: 升目の座標) -> 升目の座標ソース {
    升目の座標ソース {
        横: 座標.横,
        奥: 座標.奥,
        階: 座標.階,
    }
}

fn 升目を写す(升目: 升目の宣言) -> 升目ソース {
    升目ソース {
        座標: 座標を写す(升目.座標),
        正面: はめ口を写す(升目.正面),
        背面: はめ口を写す(升目.背面),
        左面: はめ口を写す(升目.左面),
        右面: はめ口を写す(升目.右面),
        床: match 升目.床 {
            升目の床::張らない => 升目の床ソース::張らない,
            升目の床::張る => 升目の床ソース::張る,
        },
        屋根: match 升目.屋根 {
            升目の屋根::載せない => 升目の屋根ソース::載せない,
            升目の屋根::載せる => 升目の屋根ソース::載せる,
        },
    }
}

fn はめ口を写す(値: はめ口の値) -> はめ口ソース {
    match 値 {
        はめ口の値::入れない => はめ口ソース::入れない,
        はめ口の値::壁を入れる {
            壁の種類, 外面の飾り
        } => はめ口ソース::壁を入れる {
            壁の種類: 壁の種類を写す(壁の種類),
            外面の飾り: 飾りを写す(外面の飾り),
        },
    }
}

fn 壁の種類を写す(種類: 壁の種類) -> 壁の種類ソース {
    match 種類 {
        壁の種類::平壁 => 壁の種類ソース::平壁,
        壁の種類::窓壁 => 壁の種類ソース::窓壁,
        壁の種類::扉枠付きの壁 => 壁の種類ソース::扉枠付きの壁,
    }
}

fn 飾りを写す(飾り: 壁の外面の飾り) -> 壁の外面の飾りソース {
    match 飾り {
        壁の外面の飾り::付けない => 壁の外面の飾りソース::付けない,
        壁の外面の飾り::出窓を差し込む => 壁の外面の飾りソース::出窓を差し込む,
        壁の外面の飾り::煙突を立てる { 段数 } => 壁の外面の飾りソース::煙突を立てる { 段数 },
    }
}
