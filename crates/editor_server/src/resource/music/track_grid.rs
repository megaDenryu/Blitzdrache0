//! トラック1本ぶんの打ち込みの格子の型契約。行がそのトラックの音の並びの1行に、列が32のステップに対応する。
//!
//! セルの値をこの層が0から4の整数で持つのは、JSONの直列化の都合である。この数値を打点・伸ばし・
//! 制約の外の区別へ解くのはブラウザの編集モデルであり、その変換は境界1箇所に閉じる
//! (参照: `_doc/設計/楽曲エディター.md`「判断3」)。

use serde::{Deserialize, Serialize};

use super::super::numeric_check::整数が範囲内であることを確かめる;
use super::super::validation_error::資源検証エラー;

pub const パターンのステップ数: usize = 32;
const セルの値の上限: u8 = 4;

/// トラックの格子とは、1つのパターンの中でトラック1本が鳴らす音を、行と32のステップの表で表したもののことである。
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
pub struct トラックの格子 {
    pub 行一覧: Vec<Vec<u8>>,
}

impl トラックの格子 {
    /// 行の本数がトラックの音の並びと同じで、各行が32のステップを持ち、各セルの値が0から4に収まることを確かめる。
    pub(super) fn 音の並びに沿うことを確かめる(&self, 音の並びの行数: usize) -> Result<(), 資源検証エラー> {
        if self.行一覧.len() != 音の並びの行数 {
            return Err(資源検証エラー::件数が期待と違う {
                フィールド名: "トラックの格子.行一覧",
                期待件数: 音の並びの行数,
                実際件数: self.行一覧.len(),
            });
        }
        for 行 in &self.行一覧 {
            行1つが32のステップに収まることを確かめる(行)?;
        }
        Ok(())
    }
}

/// 依存も副作用も持たない純粋な検査のため自由関数として置く(CLAUDE.md「自由関数の許容2条件」(a))。
fn 行1つが32のステップに収まることを確かめる(行: &[u8]) -> Result<(), 資源検証エラー> {
    if 行.len() != パターンのステップ数 {
        return Err(資源検証エラー::件数が期待と違う {
            フィールド名: "トラックの格子.行一覧の1行",
            期待件数: パターンのステップ数,
            実際件数: 行.len(),
        });
    }
    for セル in 行 {
        整数が範囲内であることを確かめる("トラックの格子.行一覧のセル", i64::from(*セル), 0, i64::from(セルの値の上限))?;
    }
    Ok(())
}
