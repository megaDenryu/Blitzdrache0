//! 保存済みの楽曲を版ごとの型で受け取り、現在の形へ一方向に変換する。
//!
//! 1つの型へ互換用の細工を足し続けず、旧版は旧版の型として丸ごと持つ(参照: グローバルCLAUDE.md
//! 「シリアライズデータの後方互換は『版ごとの型＋最新への変換』で表す」、`_doc/設計/楽曲エディター.md`「判断10」「判断16」)。
//! 現在の型へ既定値を持たせて欄の不在を埋める形は採らない。埋める値は変換の側が名指しで置く。

use serde::Deserialize;

use super::chord_progression::コード進行;
use super::mixer::ミキサー設定;
use super::music_id::楽曲ID;
use super::pattern::パターン;
use super::pattern_id::パターンID;
use super::progression_reference::コード進行参照;
use super::section::曲の節;
use super::track::トラック定義;
use super::track_grid::トラックの格子;
use super::value_range::新しいパターンの既定の小節数;
use super::{楽曲, 楽曲の現在の形式版};

/// 楽曲の版の移行エラーとは、保存済みの正本を現在の形へ写せないことのことである。
#[derive(Debug, thiserror::Error)]
pub enum 楽曲の版の移行エラー {
    #[error("楽曲の形式版{実際}には対応していない(対応版: {対応})")]
    未対応の形式版 { 実際: u32, 対応: u32 },
}

/// 形式版1のパターンとは、パターンが小節数の欄を持つ前の形のことである。32ステップの格子は小節数2として移行する。
#[derive(Debug, Clone, PartialEq, Deserialize)]
pub struct 形式版1のパターン {
    pub 名乗り: パターンID,
    pub 表示名: String,
    pub 進行の参照: コード進行参照,
    pub 格子: Vec<トラックの格子>,
}

impl 形式版1のパターン {
    /// 小節数の欄だけが無い版であるため、既定の小節数を名指しで置く。打点の位置と長さは変えない。
    pub fn 現在の形へ変換する(self) -> パターン {
        パターン {
            名乗り: self.名乗り,
            表示名: self.表示名,
            小節数: 新しいパターンの既定の小節数,
            進行の参照: self.進行の参照,
            格子: self.格子,
        }
    }
}

/// 形式版1の楽曲とは、パターンが小節数の欄を持つ前に保存された`楽曲/<楽曲ID>.json`の形のことである。
#[derive(Debug, Clone, PartialEq, Deserialize)]
pub struct 形式版1の楽曲 {
    pub 形式版: u32,
    pub 名乗り: 楽曲ID,
    pub 表示名: String,
    pub テンポ: u32,
    pub トラック構成: Vec<トラック定義>,
    pub ミキサー設定: ミキサー設定,
    pub 独自進行一覧: Vec<コード進行>,
    pub パターン一覧: Vec<形式版1のパターン>,
    pub 曲構成: Vec<曲の節>,
}

impl 形式版1の楽曲 {
    /// 形式版の数値はそのまま読み替えず捨て、現在の形式版を名指しで置く。各パターンは形式版1の変換へ委ねる。
    pub fn 現在の形へ変換する(self) -> 楽曲 {
        楽曲 {
            形式版: 楽曲の現在の形式版,
            名乗り: self.名乗り,
            表示名: self.表示名,
            テンポ: self.テンポ,
            トラック構成: self.トラック構成,
            ミキサー設定: self.ミキサー設定,
            独自進行一覧: self.独自進行一覧,
            パターン一覧: self.パターン一覧.into_iter().map(形式版1のパターン::現在の形へ変換する).collect(),
            曲構成: self.曲構成,
        }
    }
}

/// 形式版を持たない旧版の楽曲とは、楽曲の資源に形式版の欄を足す前に保存された`楽曲/<楽曲ID>.json`の形のことである。
#[derive(Debug, Clone, PartialEq, Deserialize)]
pub struct 形式版を持たない旧版の楽曲 {
    pub 名乗り: 楽曲ID,
    pub 表示名: String,
    pub テンポ: u32,
    pub トラック構成: Vec<トラック定義>,
    pub ミキサー設定: ミキサー設定,
    pub 独自進行一覧: Vec<コード進行>,
    pub パターン一覧: Vec<形式版1のパターン>,
    pub 曲構成: Vec<曲の節>,
}

impl 形式版を持たない旧版の楽曲 {
    /// 形式版の欄だけが無い版であるため、現在の形式版を名指しで置いてから形式版1の変換へ経由する。
    pub fn 現在の形へ変換する(self) -> 楽曲 {
        形式版1の楽曲 {
            形式版: 楽曲の現在の形式版,
            名乗り: self.名乗り,
            表示名: self.表示名,
            テンポ: self.テンポ,
            トラック構成: self.トラック構成,
            ミキサー設定: self.ミキサー設定,
            独自進行一覧: self.独自進行一覧,
            パターン一覧: self.パターン一覧,
            曲構成: self.曲構成,
        }
        .現在の形へ変換する()
    }
}

/// 読み込んだ楽曲の版とは、保存されているJSONがどの版の形で書かれていたかを表す判別のことである。
/// 現在の形から順に当てはめ、当てはまった形をその版と決める(パターンの小節数の欄の有無、形式版の欄の有無で分かれる)。
#[derive(Debug, Clone, PartialEq, Deserialize)]
#[serde(untagged)]
pub enum 読み込んだ楽曲の版 {
    現在(楽曲),
    形式版1(形式版1の楽曲),
    形式版を持たない旧版(形式版を持たない旧版の楽曲),
}

impl 読み込んだ楽曲の版 {
    /// 現在より新しい形式版のファイルは、欄の意味が分からないまま現在の型として扱わず、読みの時点で拒む。
    /// 無言で受けると、読んだ側は現在の形だと思って画面へ出し、次の保存でその形へ書き潰す。
    pub fn 現在の形へ変換する(self) -> Result<楽曲, 楽曲の版の移行エラー> {
        match self {
            Self::現在(読んだ楽曲) if 読んだ楽曲.形式版 != 楽曲の現在の形式版 => {
                Err(楽曲の版の移行エラー::未対応の形式版 {
                    実際: 読んだ楽曲.形式版,
                    対応: 楽曲の現在の形式版,
                })
            }
            Self::現在(読んだ楽曲) => Ok(読んだ楽曲),
            Self::形式版1(旧版) => Ok(旧版.現在の形へ変換する()),
            Self::形式版を持たない旧版(旧版) => Ok(旧版.現在の形へ変換する()),
        }
    }
}
