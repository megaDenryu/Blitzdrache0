//! 楽曲の型契約が課す値の範囲の正本。検証はここの定数を引き、`編集資源契約.ts`はここの定数を値として出す。
//!
//! 1つの表へ集めるのは、同じ範囲を2箇所へ書く事故を防ぐためである。実際に音量とミキサーの比はどちらも0から1で、
//! 型ごとに別々の定数を持っていた。ブラウザが自分で数を書くと3つ目の写しになるため、検証が引くこの定数を
//! そのまま書き出す(参照: `_doc/設計/楽曲エディター.md`「判断9」と同じ規律)。
//!
//! 格子のセルの値だけは契約へ出さない。0から4の各値は範囲ではなく打点なし・音の始まり・音の継続・
//! 進行の外の区別であり、その意味への変換はブラウザの編集モデルが持つ(判断3)。範囲だけを配ると意味が伝わらない。

pub const 小節あたりのステップ数: usize = 16;
pub const 新しいパターンの既定の小節数: u32 = 2;
pub const パターンの小節数の上限: u32 = 64;
pub const テンポの下限: u32 = 40;
pub const テンポの上限: u32 = 300;
pub const 曲の節の繰り返し回数の下限: u32 = 1;
pub const 曲の節の繰り返し回数の上限: u32 = 8;
pub const 音高番号の下限: u8 = 0;
pub const 音高番号の上限: u8 = 127;
pub const 和音の根音の下限: u8 = 0;
pub const 和音の根音の上限: u8 = 11;
pub const 和音の続くステップ数の下限: u32 = 1;
pub const 和音の続くステップ数の上限: u32 = 32;
pub const 音量と効果の比の下限: f64 = 0.0;
pub const 音量と効果の比の上限: f64 = 1.0;
pub const 遅延のステップ数の下限: u32 = 0;
pub const 遅延のステップ数の上限: u32 = 32;
pub(super) const 格子のセルの値の下限: u8 = 0;
pub(super) const 格子のセルの値の上限: u8 = 4;

/// パターンの小節数から、その格子の1行が持つべきステップ数(小節数×小節あたりのステップ数)を求める。
pub(super) fn 小節数からステップ数を求める(小節数: u32) -> usize {
    usize::try_from(小節数).unwrap_or(usize::MAX).saturating_mul(小節あたりのステップ数)
}

/// ステップの位置は0から始まるため、格子の長さの1つ手前が上限である。数を別に持たず長さから導く。
pub(super) fn ステップの位置の上限(小節数: u32) -> i64 {
    i64::try_from(小節数からステップ数を求める(小節数)).unwrap_or(i64::MAX) - 1
}
