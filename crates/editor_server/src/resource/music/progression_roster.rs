//! 進行の名簿: 1つの楽曲の中でコード進行参照が解決できる先の集まりを持ち、参照が解決できるかを答える型。
//!
//! 独自の進行の名前の重複を組み立てのときに拒むのは、同じ名前が2つある名簿では参照がどちらを指すか
//! 決まらないためである。決まらない名簿を作らせなければ、参照の解決は必ず1件に定まる。

use super::super::validation_error::資源検証エラー;
use super::chord_progression::コード進行;
use super::preset_progression::備え付けの進行の識別子か;
use super::progression_reference::コード進行参照;

/// 進行の名簿とは、楽曲が持つ独自進行一覧と実装が備え付けで持つ既定のコード進行を合わせた、
/// コード進行参照の解決先の集まりのことである。
pub(super) struct 進行の名簿<'楽曲の借り> {
    独自進行一覧: &'楽曲の借り [コード進行],
}

impl<'楽曲の借り> 進行の名簿<'楽曲の借り> {
    /// 独自進行一覧の各件を検証しつつ、名前が重複していないことを確かめてから名簿にする。
    pub(super) fn 独自進行一覧から組み立てる(
        独自進行一覧: &'楽曲の借り [コード進行]
    ) -> Result<Self, 資源検証エラー> {
        for (位置, 進行) in 独自進行一覧.iter().enumerate() {
            進行.検証する()?;
            if 独自進行一覧[..位置].iter().any(|先に見た進行| 先に見た進行.名前 == 進行.名前) {
                return Err(資源検証エラー::名前が重複している {
                    フィールド名: "楽曲.独自進行一覧.名前",
                    値: 進行.名前.clone(),
                });
            }
        }
        Ok(Self { 独自進行一覧 })
    }

    pub(super) fn 参照が解決できることを確かめる(&self, 参照: &コード進行参照) -> Result<(), 資源検証エラー> {
        match 参照 {
            コード進行参照::既定の進行 { 識別子 } if 備え付けの進行の識別子か(識別子) => Ok(()),
            コード進行参照::既定の進行 { 識別子 } => Err(資源検証エラー::参照先が存在しない {
                フィールド名: "コード進行参照.既定の進行.識別子",
                値: 識別子.clone(),
            }),
            コード進行参照::独自の進行 { 名前 } if self.独自進行一覧.iter().any(|進行| &進行.名前 == 名前) => Ok(()),
            コード進行参照::独自の進行 { 名前 } => Err(資源検証エラー::参照先が存在しない {
                フィールド名: "コード進行参照.独自の進行.名前",
                値: 名前.clone(),
            }),
        }
    }
}
