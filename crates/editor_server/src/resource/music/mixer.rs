//! ミキサー設定の型契約。全体の音量・残響の量・遅延の量を0から1の比で、遅延の長さをステップ数で持つ。
//!
//! 比を素の`f64`で持つのは、この層がJSONの直列化境界に接するためである。単位と値域を型で守るのは
//! 境界の内側にあるブラウザの編集モデルの担当である(参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断8」)。

use serde::{Deserialize, Serialize};

use super::super::numeric_check::{小数が範囲内であることを確かめる, 整数が範囲内であることを確かめる};
use super::super::validation_error::資源検証エラー;
use super::value_range::{
    遅延のステップ数の上限, 遅延のステップ数の下限, 音量と効果の比の上限, 音量と効果の比の下限
};

/// ミキサー設定とは、曲全体へまとめて掛かる音量と効果の量の指定のことである。
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
pub struct ミキサー設定 {
    pub 全体の音量: f64,
    pub 残響の量: f64,
    pub 遅延の量: f64,
    pub 遅延のステップ数: u32,
}

impl ミキサー設定 {
    pub(super) fn 検証する(&self) -> Result<(), 資源検証エラー> {
        小数が範囲内であることを確かめる("ミキサー設定.全体の音量", self.全体の音量, 音量と効果の比の下限, 音量と効果の比の上限)?;
        小数が範囲内であることを確かめる("ミキサー設定.残響の量", self.残響の量, 音量と効果の比の下限, 音量と効果の比の上限)?;
        小数が範囲内であることを確かめる("ミキサー設定.遅延の量", self.遅延の量, 音量と効果の比の下限, 音量と効果の比の上限)?;
        整数が範囲内であることを確かめる(
            "ミキサー設定.遅延のステップ数",
            i64::from(self.遅延のステップ数),
            i64::from(遅延のステップ数の下限),
            i64::from(遅延のステップ数の上限),
        )
    }
}
