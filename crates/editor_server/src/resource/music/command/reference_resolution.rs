//! コマンドの指し先の解決係: 1つの楽曲を借りて、操作コマンドが指すトラック・パターン・節・進行が
//! 実在するかを答える型。
//!
//! 楽曲を借りて型に保持させるのは、各コマンドの検証が楽曲を引数で持ち回らずに済むようにするためである
//! (グローバルCLAUDE.md「操作の所有者を外部引数にしない」)。ここが答えるのは指し先が実在するかどうかだけであり、
//! コマンドを楽曲へ適用する実装は持たない(参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断1」)。

use crate::resource::music::progression_roster::進行の名簿;
use crate::resource::validation_error::資源検証エラー;
use crate::resource::{コード進行参照, トラック定義, パターン, パターンID, 楽曲};

pub(super) struct コマンドの指し先の解決係<'楽曲の借り> {
    対象の楽曲: &'楽曲の借り 楽曲,
}

impl<'楽曲の借り> コマンドの指し先の解決係<'楽曲の借り> {
    pub(super) fn 楽曲を借りて生成する(対象の楽曲: &'楽曲の借り 楽曲) -> Self {
        Self { 対象の楽曲 }
    }

    /// 位置で指したトラックを引く。楽器の組み合わせの検査が引いたトラックの種類を要するため、位置の判定だけでなく本体を返す。
    pub(super) fn トラックを引く(&self, トラックの位置: u32) -> Result<&トラック定義, 資源検証エラー> {
        let 位置 = usize::try_from(トラックの位置).unwrap_or(usize::MAX);
        self.対象の楽曲.トラック構成.get(位置).ok_or(資源検証エラー::整数が範囲外 {
            フィールド名: "楽曲編集コマンド.トラックの位置",
            値: i64::from(トラックの位置),
            最小: 0,
            最大: 上限の位置(self.対象の楽曲.トラック構成.len()),
        })
    }

    pub(super) fn パターンを引く(&self, 名乗り: &パターンID) -> Result<&パターン, 資源検証エラー> {
        self.対象の楽曲
            .パターン一覧
            .iter()
            .find(|パターン| &パターン.名乗り == 名乗り)
            .ok_or_else(|| 資源検証エラー::参照先が存在しない {
                フィールド名: "楽曲編集コマンド.パターンの名乗り",
                値: 名乗り.綴り().to_string(),
            })
    }

    /// 追加のコマンドは、まだ使われていない名乗りだけを受け入れる。既にある名乗りを通すと、どちらのパターンを指すか決まらなくなる。
    pub(super) fn 名乗りが未使用であることを確かめる(&self, 名乗り: &パターンID) -> Result<(), 資源検証エラー> {
        if self.パターンを引く(名乗り).is_err() {
            return Ok(());
        }
        Err(資源検証エラー::名前が重複している {
            フィールド名: "楽曲編集コマンド.パターンの名乗り",
            値: 名乗り.綴り().to_string(),
        })
    }

    pub(super) fn 節の位置が曲構成の内側であることを確かめる(&self, 節の位置: u32) -> Result<(), 資源検証エラー> {
        let 位置 = usize::try_from(節の位置).unwrap_or(usize::MAX);
        if 位置 < self.対象の楽曲.曲構成.len() {
            return Ok(());
        }
        Err(資源検証エラー::整数が範囲外 {
            フィールド名: "楽曲編集コマンド.節の位置",
            値: i64::from(節の位置),
            最小: 0,
            最大: 上限の位置(self.対象の楽曲.曲構成.len()),
        })
    }

    /// 挿入は末尾への追加も兼ねるため、内側の判定と違い曲構成の長さそのものも受け入れる。
    pub(super) fn 節の挿入位置が曲構成の範囲内であることを確かめる(&self, 節の位置: u32) -> Result<(), 資源検証エラー> {
        let 位置 = usize::try_from(節の位置).unwrap_or(usize::MAX);
        if 位置 <= self.対象の楽曲.曲構成.len() {
            return Ok(());
        }
        Err(資源検証エラー::整数が範囲外 {
            フィールド名: "楽曲編集コマンド.節の位置",
            値: i64::from(節の位置),
            最小: 0,
            最大: i64::try_from(self.対象の楽曲.曲構成.len()).unwrap_or(i64::MAX),
        })
    }

    pub(super) fn 進行の参照が解決できることを確かめる(&self, 参照: &コード進行参照) -> Result<(), 資源検証エラー> {
        進行の名簿::独自進行一覧から組み立てる(&self.対象の楽曲.独自進行一覧)?.参照が解決できることを確かめる(参照)
    }

    pub(super) fn 独自の進行が実在することを確かめる(&self, 名前: &str) -> Result<(), 資源検証エラー> {
        if self.対象の楽曲.独自進行一覧.iter().any(|進行| 進行.名前 == 名前) {
            return Ok(());
        }
        Err(資源検証エラー::参照先が存在しない {
            フィールド名: "楽曲編集コマンド.独自の進行の名前",
            値: 名前.to_string(),
        })
    }
}

/// 件数から、指せる位置の上限を出す。0件のときは指せる位置が無いため、エラー文の上限は-1になる。
fn 上限の位置(件数: usize) -> i64 {
    i64::try_from(件数).unwrap_or(i64::MAX) - 1
}
