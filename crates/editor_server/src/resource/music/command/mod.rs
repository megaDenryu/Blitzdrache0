//! 楽曲の操作コマンドの型契約。人間の画面操作とAIのヘッドレス操作の両方が、この同じ形でコマンドを積む。
//!
//! ここが持つのはコマンドの直列化形と、そのコマンド自身が満たすべき値の範囲・指し先の実在の検証までである。
//! **コマンドを楽曲へ適用する実装は持たない。** 適用の意味の正本はブラウザのTypeScript実装1つだけであり、
//! Rust側へ複製すると細部が必ず割れる(参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断1」)。
//!
//! 枝の作り方は`resource/command`の`編集コマンド`と同じ様式である。楽曲の資源型の隣へ置くのは、
//! パターン・トラック・進行の内部の判定(種類が受け入れる楽器か等)を、楽曲の外へ公開せずに使うためである。

mod note_ops;
mod pattern_ops;
mod progression_ops;
mod reference_resolution;
mod section_ops;
mod song_settings_ops;
mod target;
mod track_ops;

use serde::{Deserialize, Serialize};

use crate::resource::validation_error::資源検証エラー;
use reference_resolution::コマンドの指し先の解決係;

pub use note_ops::{パターンの打点を全部消す, 打点を消す, 打点を置く, 範囲の打点を消す, 音を伸ばす};
pub use pattern_ops::{
    パターンの表示名を変える, パターンの進行を変える, パターンを削除する, パターンを追加する
};
pub use progression_ops::{独自の進行を保存する, 独自の進行を削除する};
pub use section_ops::{曲の節を並べ替える, 曲の節を削除する, 曲の節を変える, 曲の節を追加する};
pub use song_settings_ops::{テンポを変える, ミキサー設定を変える, 楽曲の表示名を変える};
pub use target::打ち込みの対象;
pub use track_ops::{トラックの楽器を変える, トラックの進行の割り当てを変える, トラックの音量を変える};

/// 楽曲編集コマンドとは、人間の画面操作とAIのヘッドレス操作の両方が同じ形で積む、
/// 1回ぶんの楽曲の編集操作を表す判別共用体のことである。
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
#[serde(tag = "種類", content = "値")]
pub enum 楽曲編集コマンド {
    打点を置く(打点を置く),
    打点を消す(打点を消す),
    音を伸ばす(音を伸ばす),
    範囲の打点を消す(範囲の打点を消す),
    パターンの打点を全部消す(パターンの打点を全部消す),
    テンポを変える(テンポを変える),
    ミキサー設定を変える(ミキサー設定を変える),
    楽曲の表示名を変える(楽曲の表示名を変える),
    トラックの楽器を変える(トラックの楽器を変える),
    トラックの音量を変える(トラックの音量を変える),
    トラックの進行の割り当てを変える(トラックの進行の割り当てを変える),
    パターンを追加する(パターンを追加する),
    パターンを削除する(パターンを削除する),
    パターンの進行を変える(パターンの進行を変える),
    パターンの表示名を変える(パターンの表示名を変える),
    独自の進行を保存する(独自の進行を保存する),
    独自の進行を削除する(独自の進行を削除する),
    曲の節を追加する(曲の節を追加する),
    曲の節を変える(曲の節を変える),
    曲の節を削除する(曲の節を削除する),
    曲の節を並べ替える(曲の節を並べ替える),
}

impl 楽曲編集コマンド {
    /// このコマンドが対象の楽曲に対して成り立つかを確かめる。**楽曲は変えない。**
    /// 指し先が実在するかと値が範囲に収まるかだけを見る。
    pub fn 検証する(&self, 対象の楽曲: &crate::resource::楽曲) -> Result<(), 資源検証エラー> {
        let 解決係 = コマンドの指し先の解決係::楽曲を借りて生成する(対象の楽曲);
        match self {
            Self::打点を置く(コマンド) => コマンド.検証する(&解決係),
            Self::打点を消す(コマンド) => コマンド.検証する(&解決係),
            Self::音を伸ばす(コマンド) => コマンド.検証する(&解決係),
            Self::範囲の打点を消す(コマンド) => コマンド.検証する(&解決係),
            Self::パターンの打点を全部消す(コマンド) => コマンド.検証する(&解決係),
            Self::テンポを変える(コマンド) => コマンド.検証する(),
            Self::ミキサー設定を変える(コマンド) => コマンド.検証する(),
            Self::楽曲の表示名を変える(コマンド) => コマンド.検証する(),
            Self::トラックの楽器を変える(コマンド) => コマンド.検証する(&解決係),
            Self::トラックの音量を変える(コマンド) => コマンド.検証する(&解決係),
            Self::トラックの進行の割り当てを変える(コマンド) => コマンド.検証する(&解決係),
            Self::パターンを追加する(コマンド) => コマンド.検証する(&解決係),
            Self::パターンを削除する(コマンド) => コマンド.検証する(&解決係),
            Self::パターンの進行を変える(コマンド) => コマンド.検証する(&解決係),
            Self::パターンの表示名を変える(コマンド) => コマンド.検証する(&解決係),
            Self::独自の進行を保存する(コマンド) => コマンド.検証する(),
            Self::独自の進行を削除する(コマンド) => コマンド.検証する(&解決係),
            Self::曲の節を追加する(コマンド) => コマンド.検証する(&解決係),
            Self::曲の節を変える(コマンド) => コマンド.検証する(&解決係),
            Self::曲の節を削除する(コマンド) => コマンド.検証する(&解決係),
            Self::曲の節を並べ替える(コマンド) => コマンド.検証する(&解決係),
        }
    }
}
