//! パターンの名簿: 1つの楽曲が持つパターンの名乗りの集まりを持ち、曲構成の指す先が実在するかを答える型。
//!
//! 名乗りの重複を組み立てのときに拒むのは、同じ名乗りが2つある名簿では節がどちらのパターンを指すか
//! 決まらないためである。決まらない名簿を作らせなければ、節の解決は必ず1件に定まる。

use super::super::validation_error::資源検証エラー;
use super::pattern::パターン;
use super::pattern_id::パターンID;

/// パターンの名簿とは、楽曲が持つパターン一覧を、名乗りの重複が無いことを確かめた上で束ねたもののことである。
pub(super) struct パターンの名簿<'楽曲の借り> {
    パターン一覧: &'楽曲の借り [パターン],
}

impl<'楽曲の借り> パターンの名簿<'楽曲の借り> {
    pub(super) fn パターン一覧から組み立てる(
        パターン一覧: &'楽曲の借り [パターン]
    ) -> Result<Self, 資源検証エラー> {
        for (位置, パターン) in パターン一覧.iter().enumerate() {
            if パターン一覧[..位置]
                .iter()
                .any(|先に見たパターン| 先に見たパターン.名乗り == パターン.名乗り)
            {
                return Err(資源検証エラー::名前が重複している {
                    フィールド名: "楽曲.パターン一覧.名乗り",
                    値: パターン.名乗り.綴り().to_string(),
                });
            }
        }
        Ok(Self { パターン一覧 })
    }

    pub(super) fn 名乗りが実在することを確かめる(&self, 名乗り: &パターンID) -> Result<(), 資源検証エラー> {
        if self.パターン一覧.iter().any(|パターン| &パターン.名乗り == 名乗り) {
            Ok(())
        } else {
            Err(資源検証エラー::参照先が存在しない {
                フィールド名: "曲の節.パターンの名乗り",
                値: 名乗り.綴り().to_string(),
            })
        }
    }
}
