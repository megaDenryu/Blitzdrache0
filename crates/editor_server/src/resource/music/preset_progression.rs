//! 既定のコード進行の型契約と、実装が備え付けで持つ8件を値として組み立てる口。
//!
//! 和音の中身までサーバー側の型契約が持つのは、識別子だけを配ると同じ定数の写しがブラウザ側にもでき、
//! 片方だけが変わる余地が残るためである。ブラウザは型の生成と同じ経路でこの値を受け取り、自分では定数を持たない
//! (参照: `_doc/設計/楽曲エディター.md`「判断9」)。中身の正本は`table`が持つ。

mod table;

use serde::{Deserialize, Serialize};

use super::chord::和音;
use table::{既定の進行の宣言, 既定の進行の宣言一覧};

/// 既定のコード進行とは、実装が備え付けで持つコード進行1件(参照に使う識別子・画面に出す表示名・和音の並び)のことである。
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
pub struct 既定のコード進行 {
    pub 識別子: String,
    pub 表示名: String,
    pub 和音一覧: Vec<和音>,
}

impl 既定のコード進行 {
    fn 宣言から組み立てる(宣言: &既定の進行の宣言) -> Self {
        Self {
            識別子: 宣言.識別子.to_string(),
            表示名: 宣言.表示名.to_string(),
            和音一覧: 宣言.和音一覧.to_vec(),
        }
    }
}

/// 備え付けの進行8件を値として組み立てる。型契約の書き出しとブラウザへの受け渡しがこの口を使う。
pub fn 既定のコード進行一覧() -> Vec<既定のコード進行> {
    既定の進行の宣言一覧.iter().map(既定のコード進行::宣言から組み立てる).collect()
}

/// 参照の解決が識別子の実在を見るときの引き先。一覧を組み立て直さず、宣言の表を直接見る。
pub(super) fn 備え付けの進行の識別子か(識別子: &str) -> bool {
    既定の進行の宣言一覧.iter().any(|宣言| 宣言.識別子 == 識別子)
}
