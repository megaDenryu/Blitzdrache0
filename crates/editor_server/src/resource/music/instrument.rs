//! 楽器と打楽器の種類の型契約。
//!
//! 合成の技法そのものは汎用の音声ライブラリが持ち、その技法を特定の音色として名づけたこの一覧は
//! エディター側にある(参照: `_doc/設計/楽曲エディター.md`「判断1」)。

use serde::{Deserialize, Serialize};

/// 楽器とは、トラックの音をブラウザが鳴らすときに選ぶ音色の名前のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
pub enum 楽器 {
    グランドピアノ,
    弦楽合奏,
    フルート,
    矩形波の主旋律,
    アコースティックギター,
    エレクトリックピアノ,
    ウッドベース,
    エレキベース,
    三角波のベース,
    生ドラム,
    矩形波と雑音のドラム,
}

/// 打楽器の種類とは、打楽器のトラックの1行が受け持つ打撃音の区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
pub enum 打楽器の種類 {
    バスドラム,
    スネア,
    ハイハット,
}

/// 楽器の音の種類とは、楽器が音高を持つ音源か打楽器の音源かの区別のことである。
/// トラックの音の並び(音高の行一覧・打楽器の行一覧)の枝と対をなし、楽器を割り当ててよいかを判定する唯一の正本である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 楽器の音の種類 {
    音高,
    打楽器,
}

impl 楽器 {
    pub(super) fn 音の種類(self) -> 楽器の音の種類 {
        match self {
            楽器::生ドラム | 楽器::矩形波と雑音のドラム => 楽器の音の種類::打楽器,
            楽器::グランドピアノ
            | 楽器::弦楽合奏
            | 楽器::フルート
            | 楽器::矩形波の主旋律
            | 楽器::アコースティックギター
            | 楽器::エレクトリックピアノ
            | 楽器::ウッドベース
            | 楽器::エレキベース
            | 楽器::三角波のベース => 楽器の音の種類::音高,
        }
    }
}
