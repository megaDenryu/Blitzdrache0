//! 編集資源の各`検証する()`が使う、数値の不変条件を確かめる純粋関数群。
//! 依存も副作用も持たないため自由関数として置く(CLAUDE.md「自由関数の許容2条件」(a))。

use super::validation_error::資源検証エラー;

pub(super) fn 有限であることを確かめる(フィールド名: &'static str, 値: f64) -> Result<(), 資源検証エラー> {
    if 値.is_finite() {
        Ok(())
    } else {
        Err(資源検証エラー::有限数でない { フィールド名, 値 })
    }
}

pub(super) fn 正の有限数であることを確かめる(フィールド名: &'static str, 値: f64) -> Result<(), 資源検証エラー> {
    if 値.is_finite() && 値 > 0.0 {
        Ok(())
    } else {
        Err(資源検証エラー::正の有限数でない { フィールド名, 値 })
    }
}

pub(super) fn 非負の有限数であることを確かめる(フィールド名: &'static str, 値: f64) -> Result<(), 資源検証エラー> {
    if 値.is_finite() && 値 >= 0.0 {
        Ok(())
    } else {
        Err(資源検証エラー::正の有限数でない { フィールド名, 値 })
    }
}

pub(super) fn 最小件数以上であることを確かめる(
    フィールド名: &'static str,
    値: u32,
    最小件数: u32,
) -> Result<(), 資源検証エラー> {
    if 値 >= 最小件数 {
        Ok(())
    } else {
        Err(資源検証エラー::最小件数を下回る { フィールド名, 値 })
    }
}
