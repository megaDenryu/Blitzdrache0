//! 建物外形カタログ1冊の内容を、利用前に全件検証する。

use std::collections::HashSet;

use super::{
    建物外形カタログ, 建物外形カタログの現在の形式版, 建物外形カタログ読み込みエラー, 建物外形定義
};

impl 建物外形カタログ {
    pub(super) fn 検証する(&self) -> Result<(), 建物外形カタログ読み込みエラー> {
        if self.形式版 != 建物外形カタログの現在の形式版 {
            return Err(建物外形カタログ読み込みエラー::未対応の形式版 {
                実際: self.形式版,
                対応: 建物外形カタログの現在の形式版,
            });
        }
        let mut 識別子一覧 = HashSet::new();
        for 定義 in &self.建物定義一覧 {
            定義を検証する(定義, &mut 識別子一覧)?;
        }
        Ok(())
    }
}

fn 定義を検証する(
    定義: &建物外形定義, 識別子一覧: &mut HashSet<String>
) -> Result<(), 建物外形カタログ読み込みエラー> {
    if 定義.識別子.is_empty() || !識別子一覧.insert(定義.識別子.clone()) {
        return Err(不正(format!("建物識別子が空または重複している: {:?}", 定義.識別子)));
    }
    if 定義.表示名.is_empty() || 定義.部品の識別子一覧.is_empty() {
        return Err(不正(format!("{}の表示名または部品一覧が空である", 定義.識別子)));
    }
    if 定義.ベイ.横 == 0 || 定義.ベイ.奥 == 0 || 定義.ベイ.階 == 0 {
        return Err(不正(format!("{}のベイ構造に0が含まれる", 定義.識別子)));
    }
    if !定義.高さメートル.is_finite() || 定義.高さメートル <= 0.0 {
        return Err(不正(format!("{}の高さが正の有限値ではない", 定義.識別子)));
    }
    if !入口方向を利用できるか(定義) {
        return Err(不正(format!("{}の入口方向が不正である", 定義.識別子)));
    }
    for 軸 in 0..3 {
        let 最小 = 定義.外接箱.最小[軸];
        let 最大 = 定義.外接箱.最大[軸];
        if !最小.is_finite() || !最大.is_finite() || 最小 > 最大 {
            return Err(不正(format!("{}の外接箱が不正である", 定義.識別子)));
        }
    }
    let 外接箱の高さ = 定義.外接箱.最大[1] - 定義.外接箱.最小[1];
    if (定義.高さメートル - 外接箱の高さ).abs() > 0.001 {
        return Err(不正(format!("{}の高さと外接箱が一致しない", 定義.識別子)));
    }
    Ok(())
}

fn 入口方向を利用できるか(定義: &建物外形定義) -> bool {
    let 入口 = 定義.入口のローカル方向;
    入口.x.is_finite() && 入口.z.is_finite() && (入口.x.powi(2) + 入口.z.powi(2)).sqrt() > 0.0
}

fn 不正(説明: String) -> 建物外形カタログ読み込みエラー {
    建物外形カタログ読み込みエラー::内容が不正(説明)
}

