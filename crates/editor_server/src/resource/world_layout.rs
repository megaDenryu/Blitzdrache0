//! 世界の区画割りの型契約。大域世界を何メートル四方、何チャンク四方、
//! チャンクあたり何格子で持つかを定義し、マザーハイトマップとチャンク格子の
//! 寸法をここから導出する。導出式は`_doc/計画/ゲーム開発用エディター計画.md`の
//! モックアップ仕様(1024m・4×4チャンク・チャンク解像度128→513×513)に対応する。

use serde::{Deserialize, Serialize};

use super::numeric_check::{最小件数以上であることを確かめる, 正の有限数であることを確かめる};
use super::validation_error::資源検証エラー;

/// 世界の区画割りとは、大域世界の1辺の長さと、それを何チャンク四方・
/// チャンクあたり何格子で区切るかを定める値のことである。
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
pub struct 世界の区画割り {
    pub 一辺のメートル: f64,
    pub 軸あたりチャンク数: u32,
    pub チャンクあたり格子解像度: u32,
}

impl 世界の区画割り {
    pub fn 検証する(&self) -> Result<(), 資源検証エラー> {
        正の有限数であることを確かめる("世界の区画割り.一辺のメートル", self.一辺のメートル)?;
        最小件数以上であることを確かめる("世界の区画割り.軸あたりチャンク数", self.軸あたりチャンク数, 1)?;
        最小件数以上であることを確かめる("世界の区画割り.チャンクあたり格子解像度", self.チャンクあたり格子解像度, 1)?;
        Ok(())
    }

    /// マザーハイトマップの1辺の頂点数。`軸あたりチャンク数 × チャンクあたり格子解像度 + 1`。
    /// 1024m・4×4チャンク・チャンク解像度128の既定値では513になる。
    pub fn マザーハイトマップの格子解像度(&self) -> Result<u32, 資源検証エラー> {
        self.チャンクあたり格子解像度
            .checked_mul(self.軸あたりチャンク数)
            .and_then(|積| 積.checked_add(1))
            .ok_or_else(|| 資源検証エラー::数値変換に失敗 {
                説明: "軸あたりチャンク数とチャンクあたり格子解像度の積が桁あふれした".to_string(),
            })
    }

    /// 1チャンク単独の編集格子(高さ・材質重み)の1辺の頂点数。`チャンクあたり格子解像度 + 1`。
    /// 隣接チャンクとの境界頂点を共有する1px重複共有の規約(モックアップ仕様)に合わせる。
    pub fn チャンク格子の頂点数(&self) -> Result<u32, 資源検証エラー> {
        self.チャンクあたり格子解像度
            .checked_add(1)
            .ok_or_else(|| 資源検証エラー::数値変換に失敗 {
                説明: "チャンクあたり格子解像度+1が桁あふれした".to_string(),
            })
    }
}
