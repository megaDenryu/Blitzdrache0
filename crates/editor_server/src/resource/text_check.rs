//! 編集資源の各`検証する()`が使う、文字列の不変条件を確かめる純粋関数。
//! 依存も副作用も持たないため自由関数として置く(CLAUDE.md「自由関数の許容2条件」(a))。

use super::validation_error::資源検証エラー;

/// 空白だけの文字列も空として拒む。人の目には名前が入っているように見えず、一覧に並べても区別が付かないためである。
pub(super) fn 文字列が空でないことを確かめる(フィールド名: &'static str, 文字列: &str) -> Result<(), 資源検証エラー> {
    if 文字列.trim().is_empty() { Err(資源検証エラー::文字列が空 { フィールド名 }) } else { Ok(()) }
}
