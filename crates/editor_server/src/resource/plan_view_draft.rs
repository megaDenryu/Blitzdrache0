//! 見下ろし図の下書きの型契約。チャンク構造のJSONへ併存して保存する編集資源であり、高さ格子と材質重みの正本を
//! 生成するための入力である(正本ではない)。
//! 参照: `_doc/設計/見下ろし図による地形編集.md`「判断1」「判断4」

use std::collections::BTreeSet;

use serde::{Deserialize, Serialize};

use super::coarse_cell_paint::大升の塗り;
use super::contour_line::等高線;
use super::numeric_check::最小件数以上であることを確かめる;
use super::validation_error::資源検証エラー;

/// 大升の一辺の既定値。2メートル刻みの格子なら16メートルの大升になる(参照: 設計正本「判断4」)。
pub const 既定の大升の一辺の升目数: u32 = 8;

/// 見下ろし図の下書きとは、1チャンクの等高線一覧と大升の塗りをまとめた編集資源のことである。
/// 大升の一辺は高さ格子の升目を縦横いくつまとめるかであり、塗りの列と行はこの一辺を単位に数える。
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
pub struct 見下ろし図の下書き {
    pub 等高線一覧: Vec<等高線>,
    pub 大升の一辺の升目数: u32,
    pub 大升の塗り一覧: Vec<大升の塗り>,
}

impl 見下ろし図の下書き {
    pub fn 空の下書きを作る(大升の一辺の升目数: u32) -> Self {
        Self {
            等高線一覧: Vec::new(),
            大升の一辺の升目数,
            大升の塗り一覧: Vec::new(),
        }
    }

    pub fn 検証する(&self) -> Result<(), 資源検証エラー> {
        最小件数以上であることを確かめる("見下ろし図の下書き.大升の一辺の升目数", self.大升の一辺の升目数, 1)?;
        for 等高線 in &self.等高線一覧 {
            等高線.検証する()?;
        }
        let mut 見た位置 = BTreeSet::new();
        for 塗り in &self.大升の塗り一覧 {
            塗り.検証する()?;
            if !見た位置.insert((塗り.列, 塗り.行)) {
                return Err(資源検証エラー::組み合わせが成り立たない {
                    フィールド名: "見下ろし図の下書き.大升の塗り一覧",
                    説明: format!("列{}行{}の大升の塗りが2つ以上ある", 塗り.列, 塗り.行),
                });
            }
        }
        Ok(())
    }

    /// 区画割りを知る場所(チャンク構造の保存経路)が呼ぶ。下書き自身は区画割りを持たないため`検証する`には含めない。
    pub fn 大升の一辺が格子解像度を割り切ることを確かめる(
        一辺: u32, 格子解像度: u32
    ) -> Result<(), 資源検証エラー> {
        最小件数以上であることを確かめる("見下ろし図の下書き.大升の一辺の升目数", 一辺, 1)?;
        if 格子解像度.is_multiple_of(一辺) {
            Ok(())
        } else {
            Err(資源検証エラー::組み合わせが成り立たない {
                フィールド名: "見下ろし図の下書き.大升の一辺の升目数",
                説明: format!("一辺{一辺}はチャンクあたり格子解像度{格子解像度}を割り切らない"),
            })
        }
    }
}
