//! チャンク構造の型契約。`GET|PUT /api/チャンク/{x}/{z}/構造`が読み書きするJSONの正本であり、
//! 道路一覧・建物一覧・散布の設定・散布の個体一覧を1つの直列化単位へ束ねる(高さ格子・材質重みは別口のバイナリ資源)。
//!
//! 散布の個体一覧が設定と並んで載るのは、ポアソンディスクの計算の正本がブラウザ側の編集モデルにあり、
//! 編集サーバーとアセットコンパイラがその計算を持たないためである。編集モデルが確定させた個体の列を
//! そのまま保存し、書き出しがエディターチャンクソースへ写す。
//!
//! 見下ろし図の下書きが併存して載るのは、下書きが高さ格子と材質重みの正本を生成するための入力であり、
//! 正本のバイナリ資源を変えずにチャンクへ紐づけて保存するためである(参照: `_doc/設計/見下ろし図による地形編集.md`「判断1」)。

use serde::{Deserialize, Serialize};

use super::building::建物の配置;
use super::chunk_road::チャンクの道路;
use super::plan_view_draft::見下ろし図の下書き;
use super::scatter_settings::散布の設定;
use super::scattered_individual::散布の個体;
use super::validation_error::資源検証エラー;

/// チャンク構造とは、1チャンクの道路一覧・建物一覧・散布の設定・散布の個体一覧・見下ろし図の下書きをまとめた、
/// `チャンク/{x}/{z}/構造`のJSON1本ぶんの内容のことである。道路は分岐して枝分かれするため、
/// 1チャンクに何本でも置ける一覧で持つ(1本も無い状態は空の列で表す)。
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "typescript", derive(ts_rs::TS))]
pub struct チャンク構造 {
    pub 道路一覧: Vec<チャンクの道路>,
    pub 建物一覧: Vec<建物の配置>,
    pub 散布: 散布の設定,
    pub 散布の個体一覧: Vec<散布の個体>,
    pub 見下ろし図の下書き: 見下ろし図の下書き,
}

impl チャンク構造 {
    pub fn 検証する(&self) -> Result<(), 資源検証エラー> {
        for 道路 in &self.道路一覧 {
            道路.検証する()?;
        }
        for 建物 in &self.建物一覧 {
            建物.検証する()?;
        }
        self.散布.検証する()?;
        for 個体 in &self.散布の個体一覧 {
            個体.検証する()?;
        }
        self.見下ろし図の下書き.検証する()?;
        Ok(())
    }
}
