//! 曲げ拘束の生成: 格子の内側の辺(横・縦・斜め)ごとに、その辺を共有する2つの三角形の対を1本にする(Issue #38)。
//! 本数の理論値: 斜め=(n-1)²、横=(n-1)(n-2)、縦=(n-1)(n-2)(nは一辺粒子数)。境界の辺は三角形を1つしか持たないため持たない。
//! 4粒子の並びは描画用インデックス(`grid_indices`。1セルは(左上, 左下, 右上)と(右上, 左下, 右下))の巻き順に合わせ、
//! 三角形(辺a, 辺b, 翼c)と三角形(辺b, 辺a, 翼d)がどちらも巻き順の巡回になるように置く。平らな格子では2つの法線が一致して二面角が0である。

use super::bending_constraint::曲げ拘束;
use super::grid_index::線形添字;
use super::index_convert::u32へ;

pub(super) fn 曲げ拘束一覧を作る(一辺粒子数: usize) -> Vec<曲げ拘束> {
    let mut 拘束一覧 = Vec::new();
    for 行 in 0..一辺粒子数 {
        for 列 in 0..一辺粒子数 {
            if 行 + 1 < 一辺粒子数 && 列 + 1 < 一辺粒子数 {
                // 斜め: 左下と右上を共有する辺、翼は左上と右下
                拘束一覧.push(拘束を作る(一辺粒子数, (行 + 1, 列), (行, 列 + 1), (行, 列), (行 + 1, 列 + 1)));
            }
            if 行 > 0 && 行 + 1 < 一辺粒子数 && 列 + 1 < 一辺粒子数 {
                // 横: このセルの上の辺、翼は左下と上のセルの右上
                拘束一覧.push(拘束を作る(一辺粒子数, (行, 列 + 1), (行, 列), (行 + 1, 列), (行 - 1, 列 + 1)));
            }
            if 列 > 0 && 行 + 1 < 一辺粒子数 && 列 + 1 < 一辺粒子数 {
                // 縦: このセルの左の辺、翼は右上と左のセルの左下
                拘束一覧.push(拘束を作る(一辺粒子数, (行, 列), (行 + 1, 列), (行, 列 + 1), (行 + 1, 列 - 1)));
            }
        }
    }
    拘束一覧
}

fn 拘束を作る(
    一辺粒子数: usize,
    (行a, 列a): (usize, usize),
    (行b, 列b): (usize, usize),
    (行c, 列c): (usize, usize),
    (行d, 列d): (usize, usize),
) -> 曲げ拘束 {
    曲げ拘束 {
        辺a添字: u32へ(線形添字(一辺粒子数, 行a, 列a)),
        辺b添字: u32へ(線形添字(一辺粒子数, 行b, 列b)),
        翼c添字: u32へ(線形添字(一辺粒子数, 行c, 列c)),
        翼d添字: u32へ(線形添字(一辺粒子数, 行d, 列d)),
    }
}
