//! 布データを拘束グラフへ写す工程。受け取るのは布データと布の物性、返すのは正典式の引数(静止長・コンプライアンス)を持つ拘束グラフである。
//! 布の生値(`[f32; 3]`の位置・`f32`の逆質量と静止長)を単位を持つ型へ包み直すのはこの1箇所であり、
//! 布のGPU経路の拘束バッファも布の参照計算もこのグラフから作る。

use blitz_math::{メートル, 逆キログラム};

use super::data::布データ;
use super::material::布の物性;
use crate::constraint_graph::{拘束グラフ, 拘束グラフエラー, 添字付き距離拘束, 点添字, 点自由度の初期状態};
use crate::xpbd::{距離拘束の引数, 静止長};

impl 布データ {
    /// 粒子を点自由度へ、距離拘束を種類のコンプライアンスを持つ拘束へ写す。拘束の並びは布データの並びのままである。
    pub fn 拘束グラフへ写す(&self, 物性: &布の物性) -> Result<拘束グラフ, 拘束グラフエラー> {
        let mut 点一覧 = Vec::with_capacity(self.粒子一覧.len());
        for 粒子 in &self.粒子一覧 {
            点一覧.push(点自由度の初期状態::生成する(
                粒子.ワールド位置(),
                逆キログラム::生成する(粒子.逆質量)?,
            ));
        }
        let mut 拘束一覧 = Vec::with_capacity(self.距離拘束一覧.len());
        for 拘束 in &self.距離拘束一覧 {
            let 引数 =
                距離拘束の引数::生成する(静止長::生成する(メートル::生成する(拘束.静止長))?, 物性.種類のコンプライアンス(拘束.種類));
            拘束一覧.push(添字付き距離拘束::生成する(
                点添字::生成する(拘束.粒子a添字),
                点添字::生成する(拘束.粒子b添字),
                引数,
            )?);
        }
        拘束グラフ::生成する(点一覧, 拘束一覧)
    }
}
