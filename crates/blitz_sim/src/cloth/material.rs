//! 布の物性: 構造とせん断の距離拘束のコンプライアンス(Issue #36「物性」)と、曲げ拘束の曲げのコンプライアンス(Issue #38「拘束データ」)。
//! 硬さの正本はこの3つのコンプライアンスであり、過緩和係数は持たない(`_doc/設計/XPBD共通拘束基盤.md`「判断1」)。
//! 種類ごとに別の値を持てる型にし、初期値が同じでも型の上で分かれていることを保つ。伸びと曲げは次元の違う別の型であり、倍率で流用できない。

use super::distance_constraint::距離拘束の種類;
use crate::xpbd::{コンプライアンス, 曲げのコンプライアンス};

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 布の物性 {
    構造のコンプライアンス: コンプライアンス,
    せん断のコンプライアンス: コンプライアンス,
    曲げのコンプライアンス: 曲げのコンプライアンス,
}

impl 布の物性 {
    pub fn 生成する(
        構造のコンプライアンス: コンプライアンス,
        せん断のコンプライアンス: コンプライアンス,
        曲げのコンプライアンス: 曲げのコンプライアンス,
    ) -> Self {
        Self {
            構造のコンプライアンス,
            せん断のコンプライアンス,
            曲げのコンプライアンス,
        }
    }

    /// 構造もせん断も曲げも硬い拘束の物性。
    pub fn 硬い() -> Self {
        Self::生成する(コンプライアンス::硬い(), コンプライアンス::硬い(), 曲げのコンプライアンス::硬い())
    }

    /// 構造とせん断に同じ値を与え、曲げに別の値を与えた物性。
    pub fn 一様に生成する(
        コンプライアンス: コンプライアンス, 曲げのコンプライアンス: 曲げのコンプライアンス
    ) -> Self {
        Self::生成する(コンプライアンス, コンプライアンス, 曲げのコンプライアンス)
    }

    pub fn 曲げのコンプライアンス(&self) -> 曲げのコンプライアンス {
        self.曲げのコンプライアンス
    }

    /// 曲げのコンプライアンスだけを差し替えた物性。曲げの硬さの記録が距離の物性を保ったまま曲げを変えるときに使う。
    pub fn 曲げを差し替える(&self, 曲げのコンプライアンス: 曲げのコンプライアンス) -> Self {
        Self {
            曲げのコンプライアンス,
            ..*self
        }
    }

    pub fn 種類のコンプライアンス(&self, 種類: 距離拘束の種類) -> コンプライアンス {
        match 種類 {
            距離拘束の種類::構造 => self.構造のコンプライアンス,
            距離拘束の種類::せん断 => self.せん断のコンプライアンス,
        }
    }
}
