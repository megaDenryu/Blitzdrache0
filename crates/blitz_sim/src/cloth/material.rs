//! 布の物性: 構造とせん断の距離拘束のコンプライアンス(Issue #36「物性」)。
//! 硬さの正本はこの2つのコンプライアンスであり、過緩和係数は持たない(`_doc/設計/XPBD共通拘束基盤.md`「判断1」)。
//! 種類ごとに別の値を持てる型にし、初期値が同じでも型の上で分かれていることを保つ。

use super::distance_constraint::距離拘束の種類;
use crate::xpbd::コンプライアンス;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 布の物性 {
    構造のコンプライアンス: コンプライアンス,
    せん断のコンプライアンス: コンプライアンス,
}

impl 布の物性 {
    pub fn 生成する(
        構造のコンプライアンス: コンプライアンス, せん断のコンプライアンス: コンプライアンス
    ) -> Self {
        Self {
            構造のコンプライアンス,
            せん断のコンプライアンス,
        }
    }

    /// 構造もせん断も硬い拘束の物性。
    pub fn 硬い() -> Self {
        Self::生成する(コンプライアンス::硬い(), コンプライアンス::硬い())
    }

    /// 構造とせん断に同じ値を与えた物性。
    pub fn 一様に生成する(コンプライアンス: コンプライアンス) -> Self {
        Self::生成する(コンプライアンス, コンプライアンス)
    }

    pub fn 種類のコンプライアンス(&self, 種類: 距離拘束の種類) -> コンプライアンス {
        match 種類 {
            距離拘束の種類::構造 => self.構造のコンプライアンス,
            距離拘束の種類::せん断 => self.せん断のコンプライアンス,
        }
    }
}
