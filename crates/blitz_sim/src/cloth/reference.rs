//! 布の参照計算: 布のGPU経路(`shaders/cloth_step.slang`と`shaders/cloth_constraint.slang`と`shaders/cloth_finish.slang`)の一刻みを、正典式(`crate::xpbd`)でCPUに再現する。
//! GPUの読み戻しをこれと突き合わせるのがIssue #36の検証であり、工程は積分→乗数の零化→色順の逐次の拘束→仕上げ(床)である。
//! 介入・アタッチ・自己衝突の分離は再現しない。分離はGPUの原子加算の順序に依るため、突き合わせる布は自己衝突を行わない設定で走らせる
//! (`blitz_render::布の自己衝突::行わない`)。介入とアタッチも0件の条件だけを扱う。
//! 速度は位置と刻みの開始の位置の差で表す(ベルレ形)。GPUは速度を別に持つが、仕上げが速度を(位置 − 刻みの開始の位置)÷刻み幅×減衰で作り直し、
//! 積分がその速度に重力を足して刻み幅を掛けるため、両者の差は単精度の丸めの桁である。一刻みの工程は`step`が持つ。

mod error;
mod step;

use blitz_math::{ワールド, 位置, 逆キログラム};

pub use error::布の参照計算エラー;

use super::colored_constraints::布の彩色済み拘束;
use crate::constraint_graph::{一様な加速度, 拘束違反の二乗平均平方根, 拘束違反の平均, 添字付き距離拘束};
use crate::xpbd::{ラグランジュ乗数, 刻み幅, 距離拘束の一刻みの係数};

/// 参照計算がGPUの定数と同じ値で受ける条件。速度減衰は仕上げが速度へ掛ける無次元の比である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 布の参照計算の条件 {
    pub 刻み幅: 刻み幅,
    pub 重力: 一様な加速度,
    pub 速度減衰: f32,
}

/// 参照計算の状態。拘束の並びは彩色済み拘束の並び(色順)そのものであり、ラグランジュ乗数の並びもそれに従う。
pub struct 布の参照計算 {
    拘束一覧: Vec<添字付き距離拘束>,
    係数一覧: Vec<距離拘束の一刻みの係数>,
    逆質量一覧: Vec<逆キログラム>,
    位置一覧: Vec<位置<ワールド>>,
    刻みの開始の位置一覧: Vec<位置<ワールド>>, // 直近に進めた刻みの開始時の位置。位置との差が速度×刻み幅である
    乗数一覧: Vec<ラグランジュ乗数>,
    条件: 布の参照計算の条件,
}

impl 布の参照計算 {
    /// 刻み幅を受けて全拘束の一刻みの係数を1度だけ導く(判断8の工程6)。初期の速度は0である。
    pub fn 生成する(拘束: &布の彩色済み拘束, 条件: 布の参照計算の条件) -> Result<Self, 布の参照計算エラー> {
        let グラフ = 拘束.拘束グラフ();
        let mut 係数一覧 = Vec::with_capacity(グラフ.拘束の数());
        for 拘束 in グラフ.拘束一覧() {
            係数一覧.push(拘束.引数.刻み幅で解く係数を導く(条件.刻み幅)?);
        }
        let 位置一覧: Vec<位置<ワールド>> = グラフ.点一覧().iter().map(|点| 点.位置).collect();
        Ok(Self {
            拘束一覧: グラフ.拘束一覧().to_vec(),
            係数一覧,
            逆質量一覧: グラフ.点一覧().iter().map(|点| 点.逆質量).collect(),
            刻みの開始の位置一覧: 位置一覧.clone(),
            乗数一覧: vec![ラグランジュ乗数::零(); グラフ.拘束の数()],
            位置一覧,
            条件,
        })
    }

    pub fn 位置一覧(&self) -> &[位置<ワールド>] {
        &self.位置一覧
    }

    /// 直近の刻みの反復を終えた時点のラグランジュ乗数。次の刻みの開始で零へ戻る。
    pub fn ラグランジュ乗数一覧(&self) -> &[ラグランジュ乗数] {
        &self.乗数一覧
    }

    pub fn 拘束一覧(&self) -> &[添字付き距離拘束] {
        &self.拘束一覧
    }

    /// 現在の位置での拘束違反の二乗平均の平方根。GPUの読み戻しにも同じ式を当てる。
    pub fn 拘束違反の二乗平均平方根(&self) -> f64 {
        拘束違反の二乗平均平方根(&self.拘束一覧, &self.位置一覧)
    }

    /// 現在の位置での拘束違反の符号付きの平均。伸びていれば正であり、硬さの記録が読む。
    pub fn 拘束違反の平均(&self) -> f64 {
        拘束違反の平均(&self.拘束一覧, &self.位置一覧)
    }
}
