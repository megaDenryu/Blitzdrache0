//! 布仕様: 布メッシュ生成のパラメータ(判断52)。

use super::error::布生成エラー;

/// 判断52の初版構成で使う一辺粒子数(32x32グリッド)。
pub const 既定一辺粒子数: u32 = 32;

/// 布の格子の行が進む向き。垂直は行が−Yへ進む吊るした形(上端の行が最上段)、水平は行が+Zへ進む敷いた形(上端の行が原点の側の縁)である。
/// 水平な布は固定した縁から重力で垂れ落ちるときに面の外へ曲がるため、曲げ拘束の検証の題材になる(垂直な布は面の内側の力しか受けず平らなままである)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 布の敷き方 {
    垂直,
    水平,
}

/// 布メッシュ生成のパラメータ。検証付き生成のみで作れる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 布仕様 {
    一辺粒子数: u32,
    粒子間隔: f32,
    総質量: f32,
    原点開始位置: [f32; 3],
    敷き方: 布の敷き方,
}

impl 布仕様 {
    /// 垂直に吊るす布の仕様。一辺粒子数2未満・65535超過・非正の粒子間隔・非正の総質量は型付きエラーで拒否する。
    /// 65535(u16の範囲)の上限は、質量計算のusize→f32変換を精度・オーバーフローの
    /// 両面で安全にするための制約(布としても非現実的な規模のため実用上の制限にならない)。
    pub fn 生成する(一辺粒子数: u32, 粒子間隔: f32, 総質量: f32, 原点開始位置: [f32; 3]) -> Result<Self, 布生成エラー> {
        Self::敷き方を選んで生成する(一辺粒子数, 粒子間隔, 総質量, 原点開始位置, 布の敷き方::垂直)
    }

    /// 水平に敷く布の仕様。検査は`生成する`と同じである。
    pub fn 水平に生成する(
        一辺粒子数: u32, 粒子間隔: f32, 総質量: f32, 原点開始位置: [f32; 3]
    ) -> Result<Self, 布生成エラー> {
        Self::敷き方を選んで生成する(一辺粒子数, 粒子間隔, 総質量, 原点開始位置, 布の敷き方::水平)
    }

    fn 敷き方を選んで生成する(
        一辺粒子数: u32,
        粒子間隔: f32,
        総質量: f32,
        原点開始位置: [f32; 3],
        敷き方: 布の敷き方,
    ) -> Result<Self, 布生成エラー> {
        if 一辺粒子数 < 2 {
            return Err(布生成エラー::粒子数不足 { 指定値: 一辺粒子数 });
        }
        if 一辺粒子数 > u32::from(u16::MAX) {
            return Err(布生成エラー::粒子数過大 { 指定値: 一辺粒子数 });
        }
        if 粒子間隔.is_nan() || 粒子間隔 <= 0.0 {
            return Err(布生成エラー::粒子間隔が非正 { 指定値: 粒子間隔 });
        }
        if 総質量.is_nan() || 総質量 <= 0.0 {
            return Err(布生成エラー::総質量が非正 { 指定値: 総質量 });
        }
        Ok(Self {
            一辺粒子数,
            粒子間隔,
            総質量,
            原点開始位置,
            敷き方,
        })
    }

    pub fn 敷き方(&self) -> 布の敷き方 {
        self.敷き方
    }

    pub fn 一辺粒子数(&self) -> u32 {
        self.一辺粒子数
    }

    pub fn 粒子間隔(&self) -> f32 {
        self.粒子間隔
    }

    pub fn 総質量(&self) -> f32 {
        self.総質量
    }

    pub fn 原点開始位置(&self) -> [f32; 3] {
        self.原点開始位置
    }

    /// 不変条件: `生成する`が65535以下を検証済みのため、この変換は必ず成功する。
    pub(super) fn 一辺粒子数u16(&self) -> u16 {
        match u16::try_from(self.一辺粒子数) {
            Ok(値) => 値,
            Err(_) => panic!("布仕様::生成するの検証を経ていない一辺粒子数(不変条件違反): {}", self.一辺粒子数),
        }
    }
}
