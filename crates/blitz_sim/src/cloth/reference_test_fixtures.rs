//! 布の参照計算の検査が共有する材料: 1/60秒・重力−9.8・減衰0.99の条件、上端行を固定する目標拘束のバッチ、上端を固定して垂らした布の参照計算、下端の行の平均の高さ。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{メートル毎秒毎秒, 秒};

use super::colored_constraints::布の彩色済み拘束;
use super::data::布データ;
use super::generate::布を生成する;
use super::material::布の物性;
use super::reference::{布の参照計算, 布の参照計算の条件};
use super::spec::布仕様;
use crate::constraint_graph::{一様な加速度, 添字付き目標拘束, 点添字, 目標拘束のバッチ, 目標拘束の目標};
use crate::xpbd::{刻み幅, 目標拘束の引数};

pub(super) const 間隔: f32 = 0.05;

pub(super) fn 条件() -> 布の参照計算の条件 {
    布の参照計算の条件 {
        刻み幅: 刻み幅::生成する(秒::生成する(1.0 / 60.0)).unwrap(),
        重力: 一様な加速度::成分から生成する(
            メートル毎秒毎秒::生成する(0.0),
            メートル毎秒毎秒::生成する(-9.8),
            メートル毎秒毎秒::生成する(0.0),
        ),
        速度減衰: 0.99,
    }
}

/// 上端の行を今の位置へ硬く固定する世界固定点の目標拘束と、追加の目標拘束。
pub(super) fn 上端行を固定する目標拘束(
    布: &布データ, 追加: Vec<(添字付き目標拘束, 目標拘束の目標)>
) -> 目標拘束のバッチ {
    let mut 一覧: Vec<_> = 布
        .上端行の粒子添字一覧
        .iter()
        .map(|&添字| {
            let 粒子 = 布.粒子一覧[usize::try_from(添字).unwrap()];
            (
                添字付き目標拘束::生成する(点添字::生成する(添字), 目標拘束の引数::硬い()),
                目標拘束の目標::有効な位置(粒子.ワールド位置()),
            )
        })
        .collect();
    一覧.extend(追加);
    目標拘束のバッチ::生成する(布.粒子一覧.len(), 一覧).unwrap()
}

/// 上端の行を固定して原点から垂らした布の参照計算。
pub(super) fn 吊るした布(
    一辺: u32, 原点y: f32, 物性: &布の物性, 追加の目標拘束: Vec<(添字付き目標拘束, 目標拘束の目標)>
) -> 布の参照計算 {
    let 布 = 布を生成する(&布仕様::生成する(一辺, 間隔, 4.0, [0.0, 原点y, 0.0]).unwrap()).unwrap();
    let 目標 = 上端行を固定する目標拘束(&布, 追加の目標拘束);
    布の参照計算::生成する(&布の彩色済み拘束::生成する(&布, 物性).unwrap(), &目標, 条件()).unwrap()
}

pub(super) fn 下端の行の平均y(参照: &布の参照計算, 一辺: usize) -> f32 {
    let 一覧 = 参照.位置一覧();
    let 下端 = &一覧[一覧.len() - 一辺..];
    下端.iter().map(|位置| 位置.y().値()).sum::<f32>() / f32::from(u8::try_from(一辺).unwrap())
}
