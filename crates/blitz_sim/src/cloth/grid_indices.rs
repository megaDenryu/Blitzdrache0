//! 描画用インデックス一覧と上端行の粒子添字一覧の生成(判断52)。

use super::grid_index::線形添字;
use super::index_convert::u32へ;

/// 1セルを2三角形(左上・左下・右上/右上・左下・右下)で構成する。両面描画のため
/// 巻き順そのものに機能的な意味は無いが、一貫させる。
pub(super) fn インデックス一覧を作る(一辺粒子数: usize) -> Vec<u32> {
    let mut インデックス一覧 = Vec::new();
    for 行 in 0..一辺粒子数.saturating_sub(1) {
        for 列 in 0..一辺粒子数.saturating_sub(1) {
            let 左上 = u32へ(線形添字(一辺粒子数, 行, 列));
            let 右上 = u32へ(線形添字(一辺粒子数, 行, 列 + 1));
            let 左下 = u32へ(線形添字(一辺粒子数, 行 + 1, 列));
            let 右下 = u32へ(線形添字(一辺粒子数, 行 + 1, 列 + 1));
            インデックス一覧.extend_from_slice(&[左上, 左下, 右上, 右上, 左下, 右下]);
        }
    }
    インデックス一覧
}

/// 行0(布の上端)の粒子添字一覧。アプリがアタッチ先(例: キャラクターの背)を
/// 決めるための公開情報(blitz_simはキャラクターを知らない。判断52)。
pub(super) fn 上端行を作る(一辺粒子数: usize) -> Vec<u32> {
    (0..一辺粒子数)
        .map(|列| u32へ(線形添字(一辺粒子数, 0, 列)))
        .collect()
}
