//! usize⇔u32の変換。`布仕様::生成する`が一辺粒子数を65535以下に検証済みのため、
//! この範囲内で組み立てる粒子添字は必ずu32に収まる(不変条件。失敗時はpanicで扱う。
//! 到達したらプログラムのバグである状態のため)。

pub(super) fn usizeへ(値: u32) -> usize {
    match usize::try_from(値) {
        Ok(値) => 値,
        Err(_) => panic!("このプラットフォームのusizeが32bit未満(想定外): {値}"),
    }
}

pub(super) fn u32へ(値: usize) -> u32 {
    match u32::try_from(値) {
        Ok(値) => 値,
        Err(_) => panic!("布の添字がu32の範囲を超えている(布仕様の検証で防がれるはずの不変条件違反): {値}"),
    }
}
