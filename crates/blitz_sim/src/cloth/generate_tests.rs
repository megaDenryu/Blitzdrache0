//! 布生成の単体テスト(判断52・55): 拘束本数の理論値一致・種類の割り当て・上端行と描画用インデックスの形。

#![allow(clippy::unwrap_used)]

use super::distance_constraint::距離拘束の種類;
use super::generate::布を生成する;
use super::spec::布仕様;

fn 試験用仕様(一辺粒子数: u32) -> 布仕様 {
    布仕様::生成する(一辺粒子数, 1.0, 10.0, [0.0, 0.0, 0.0]).unwrap()
}

#[test]
fn 拘束本数が理論値と一致する() {
    let n: usize = 32;
    let 布 = 布を生成する(&試験用仕様(u32::try_from(n).unwrap())).unwrap();
    let 構造本数 = 2 * n * (n - 1);
    let せん断本数 = 2 * (n - 1) * (n - 1);
    assert_eq!(布.距離拘束一覧.len(), 構造本数 + せん断本数);
    assert_eq!(布.距離拘束一覧.iter().filter(|拘束| 拘束.種類 == 距離拘束の種類::構造).count(), 構造本数);
    assert_eq!(
        布.距離拘束一覧.iter().filter(|拘束| 拘束.種類 == 距離拘束の種類::せん断).count(),
        せん断本数
    );
}

/// 反証: 種類を静止長から推測すると、粒子間隔と斜めの長さが等しい特殊な仕様で構造とせん断が見分けられなくなる。
#[test]
fn 構造は粒子間隔でせん断は斜めの長さを静止長に持つ() {
    let 布 = 布を生成する(&試験用仕様(4)).unwrap();
    for 拘束 in &布.距離拘束一覧 {
        let 期待 = match 拘束.種類 {
            距離拘束の種類::構造 => 1.0,
            距離拘束の種類::せん断 => 2.0f32.sqrt(),
        };
        assert!((拘束.静止長 - 期待).abs() < 1.0e-6);
    }
}

#[test]
fn 上端行の粒子添字は先頭一辺粒子数ぶんになる() {
    let n: u32 = 4;
    let 布 = 布を生成する(&試験用仕様(n)).unwrap();
    let 期待: Vec<u32> = (0..n).collect();
    assert_eq!(布.上端行の粒子添字一覧, 期待);
}

#[test]
fn 描画用インデックスは1セルあたり2三角形6添字になる() {
    let n: usize = 4;
    let 布 = 布を生成する(&試験用仕様(u32::try_from(n).unwrap())).unwrap();
    assert_eq!(布.描画用インデックス一覧.len(), (n - 1) * (n - 1) * 6);
}
