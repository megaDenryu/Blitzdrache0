//! 粒子: 布シミュレーションの1質点。

use blitz_math::{メートル, ワールド, 位置};

/// 位置と逆質量(質量の逆数)。布データ生成時は全粒子が均等質量で可動(逆質量>0)を持つ。
/// 逆質量は質量特性であり、固定・アタッチ・掴むは目標拘束の着脱で表す(判断6)。逆質量を0へ書き換える経路は無い。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 粒子 {
    pub 位置: [f32; 3],
    pub 逆質量: f32,
}

impl 粒子 {
    /// 生の3成分を座標系つきの位置へ包む。布の生値を型へ包み直す境界の1つである。
    pub fn ワールド位置(&self) -> 位置<ワールド> {
        位置::生成する(
            メートル::生成する(self.位置[0]),
            メートル::生成する(self.位置[1]),
            メートル::生成する(self.位置[2]),
        )
    }
}
