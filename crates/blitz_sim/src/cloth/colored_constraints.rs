//! 布の彩色済み拘束: 布の構造とせん断の距離拘束を、GPUがグラフ彩色の方式で解くために色ごとに並べ替えたもの
//! (`_doc/設計/XPBD共通拘束基盤.md`「判断7」の採用規則1)。布の生成時に1回だけ作り、トポロジーが固定であるため刻みごとに作り直さない。
//! 布のGPU経路の拘束バッファは並べ替えたグラフの並びで書き、色の区間はディスパッチ1回分としてプッシュ定数で渡す。

use super::data::布データ;
use super::material::布の物性;
use crate::constraint_graph::{グラフ彩色, 拘束グラフ, 拘束グラフエラー, 色の区間};

#[derive(Debug, Clone, PartialEq)]
pub struct 布の彩色済み拘束 {
    彩色: グラフ彩色,
}

impl 布の彩色済み拘束 {
    pub fn 生成する(布: &布データ, 物性: &布の物性) -> Result<Self, 拘束グラフエラー> {
        Ok(Self {
            彩色: グラフ彩色::生成する(&布.拘束グラフへ写す(物性)?),
        })
    }

    /// 色ごとに連続した並びへ組み替えたグラフ。GPUの拘束バッファと布の参照計算がこの並びを使う。
    pub fn 拘束グラフ(&self) -> &拘束グラフ {
        self.彩色.並べ替えたグラフ()
    }

    pub fn 色の区間一覧(&self) -> &[色の区間] {
        self.彩色.色の区間一覧()
    }

    pub fn 拘束の数(&self) -> usize {
        self.彩色.並べ替えたグラフ().拘束の数()
    }
}
