//! 布データを曲げ拘束のバッチへ写す工程。受け取るのは布データと布の物性、返すのは静止角と曲げのコンプライアンスを持つ曲げ拘束のバッチである。
//! 静止角は布データの初期の位置から二面角を測って決める(平らな格子では0、マントのように整形した初期形状ではその形の二面角)。
//! 初期の形が退化していて二面角を測れない拘束は型付きエラーで拒む。布のGPU経路の曲げ拘束バッファも布の参照計算もこのバッチの彩色から作る。

use super::data::布データ;
use super::material::布の物性;
use crate::constraint_graph::{拘束グラフエラー, 曲げ拘束のバッチ, 添字付き曲げ拘束, 点添字};
use crate::xpbd::{二面角の幾何, 曲げ拘束の引数, 静止角};

impl 布データ {
    /// 曲げ拘束を、初期の位置から測った静止角と物性の曲げのコンプライアンスを持つ拘束へ写す。拘束の並びは布データの並びのままである。
    pub fn 曲げ拘束のバッチへ写す(&self, 物性: &布の物性) -> Result<曲げ拘束のバッチ, 拘束グラフエラー> {
        let mut 拘束一覧 = Vec::with_capacity(self.曲げ拘束一覧.len());
        for (拘束番号, 拘束) in self.曲げ拘束一覧.iter().enumerate() {
            let 位置 = |添字: u32| self.粒子一覧[点添字::生成する(添字).配列添字()].ワールド位置();
            let 幾何 = 二面角の幾何::位置から測る(位置(拘束.辺a添字), 位置(拘束.辺b添字), 位置(拘束.翼c添字), 位置(拘束.翼d添字))
                .map_err(|退化| 拘束グラフエラー::曲げ拘束の初期の形が退化 { 拘束番号, 退化 })?;
            let 引数 = 曲げ拘束の引数::生成する(静止角::生成する(幾何.二面角())?, 物性.曲げのコンプライアンス());
            拘束一覧.push(添字付き曲げ拘束::生成する(
                点添字::生成する(拘束.辺a添字),
                点添字::生成する(拘束.辺b添字),
                点添字::生成する(拘束.翼c添字),
                点添字::生成する(拘束.翼d添字),
                引数,
            )?);
        }
        曲げ拘束のバッチ::生成する(self.粒子一覧.len(), 拘束一覧)
    }
}
