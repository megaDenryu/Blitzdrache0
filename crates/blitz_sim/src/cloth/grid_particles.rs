//! 粒子グリッドの生成: 行0が上端、列0が左端。行は-Y、列は+Xへ間隔ぶん並ぶ(判断52)。
//! この配置により布の先頭行(添字0..一辺粒子数)が自然に上端行になる。

use super::particle::粒子;
use super::spec::布仕様;

pub(super) fn 粒子一覧を作る(仕様: &布仕様, 一辺粒子数: usize) -> Vec<粒子> {
    let 逆質量 = 逆質量を計算する(仕様);
    let 原点 = 仕様.原点オフセット();
    let 間隔 = 仕様.粒子間隔();

    let mut 粒子一覧 = Vec::with_capacity(一辺粒子数 * 一辺粒子数);
    let mut y = 原点[1];
    for _行 in 0..一辺粒子数 {
        let mut x = 原点[0];
        for _列 in 0..一辺粒子数 {
            粒子一覧.push(粒子 {
                位置: [x, y, 原点[2]],
                逆質量,
            });
            x += 間隔;
        }
        y -= 間隔;
    }
    粒子一覧
}

/// 全粒子均等質量(判断52)。usize→f32の精度・オーバーフロー安全性は
/// `布仕様::一辺粒子数u16`のu16経由変換で保証する(直接のasキャストは使わない)。
fn 逆質量を計算する(仕様: &布仕様) -> f32 {
    let 一辺粒子数f32 = f32::from(仕様.一辺粒子数u16());
    let 粒子数f32 = 一辺粒子数f32 * 一辺粒子数f32;
    粒子数f32 / 仕様.総質量()
}
