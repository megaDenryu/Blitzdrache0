//! 距離拘束の生成: 構造(縦横隣接)+せん断(斜め隣接)。曲げ拘束は対象外(判断52)。
//! 本数の理論値: 構造=2*n*(n-1)、せん断=2*(n-1)*(n-1)(nは一辺粒子数)。

use super::distance_constraint::距離拘束;
use super::grid_index::線形添字;
use super::index_convert::u32へ;
use super::spec::布仕様;

pub(super) fn 距離拘束一覧を作る(仕様: &布仕様, 一辺粒子数: usize) -> Vec<距離拘束> {
    let 間隔 = 仕様.粒子間隔();
    let 斜め静止長 = (間隔 * 間隔 * 2.0).sqrt();
    let mut 拘束一覧 = Vec::new();

    for 行 in 0..一辺粒子数 {
        for 列 in 0..一辺粒子数 {
            if 列 + 1 < 一辺粒子数 {
                拘束一覧.push(拘束を作る(一辺粒子数, 行, 列, 行, 列 + 1, 間隔));
            }
            if 行 + 1 < 一辺粒子数 {
                拘束一覧.push(拘束を作る(一辺粒子数, 行, 列, 行 + 1, 列, 間隔));
            }
            if 行 + 1 < 一辺粒子数 && 列 + 1 < 一辺粒子数 {
                拘束一覧.push(拘束を作る(一辺粒子数, 行, 列, 行 + 1, 列 + 1, 斜め静止長));
            }
            if 行 + 1 < 一辺粒子数 && 列 > 0 {
                拘束一覧.push(拘束を作る(一辺粒子数, 行, 列, 行 + 1, 列 - 1, 斜め静止長));
            }
        }
    }
    拘束一覧
}

fn 拘束を作る(一辺粒子数: usize, 行a: usize, 列a: usize, 行b: usize, 列b: usize, 静止長: f32) -> 距離拘束 {
    距離拘束 {
        粒子a添字: u32へ(線形添字(一辺粒子数, 行a, 列a)),
        粒子b添字: u32へ(線形添字(一辺粒子数, 行b, 列b)),
        静止長,
    }
}
