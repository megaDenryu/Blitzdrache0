//! 布の参照計算の検査: 上端を固定した布が有限のまま垂れること、有限のコンプライアンスが硬い布より伸びること、
//! 床の規則が写されていることを見る。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル毎秒毎秒, 秒};

use super::colored_constraints::布の彩色済み拘束;
use super::generate::布を生成する;
use super::material::布の物性;
use super::reference::{布の参照計算, 布の参照計算の条件};
use super::spec::布仕様;
use crate::constraint_graph::一様な加速度;
use crate::xpbd::{コンプライアンス, 刻み幅};

const 間隔: f32 = 0.05;

fn 条件() -> 布の参照計算の条件 {
    布の参照計算の条件 {
        刻み幅: 刻み幅::生成する(秒::生成する(1.0 / 60.0)).unwrap(),
        重力: 一様な加速度::成分から生成する(
            メートル毎秒毎秒::生成する(0.0),
            メートル毎秒毎秒::生成する(-9.8),
            メートル毎秒毎秒::生成する(0.0),
        ),
        速度減衰: 0.99,
    }
}

/// 上端の行を固定して原点から垂らした布の参照計算。
fn 吊るした布(一辺: u32, 原点y: f32, 物性: &布の物性) -> 布の参照計算 {
    let mut 布 = 布を生成する(&布仕様::生成する(一辺, 間隔, 4.0, [0.0, 原点y, 0.0]).unwrap()).unwrap();
    for 添字 in &布.上端行の粒子添字一覧 {
        布.粒子一覧[usize::try_from(*添字).unwrap()].逆質量 = 0.0;
    }
    布の参照計算::生成する(&布の彩色済み拘束::生成する(&布, 物性).unwrap(), 条件()).unwrap()
}

fn 下端の行の平均y(参照: &布の参照計算, 一辺: usize) -> f32 {
    let 一覧 = 参照.位置一覧();
    let 下端 = &一覧[一覧.len() - 一辺..];
    下端.iter().map(|位置| 位置.y().値()).sum::<f32>() / f32::from(u8::try_from(一辺).unwrap())
}

#[test]
fn 上端を固定した硬い布は有限のまま垂れて上端は動かない() {
    let mut 参照 = 吊るした布(8, 2.0, &布の物性::硬い());
    let 初期の上端 = 参照.位置一覧()[0];
    for _ in 0..12 {
        参照.一刻み進める(4);
    }
    assert!(
        参照
            .位置一覧()
            .iter()
            .all(|位置| [位置.x(), 位置.y(), 位置.z()].iter().all(|成分| 成分.値().is_finite()))
    );
    assert_eq!(参照.位置一覧()[0], 初期の上端);
    assert!(参照.拘束違反の二乗平均平方根() < 0.05 * f64::from(間隔));
}

/// 反証: コンプライアンスを写さずに硬い拘束で解くと、柔らかい布も硬い布と同じ垂れになる。
#[test]
fn 有限のコンプライアンスは硬い布より下端が下がる() {
    let mut 硬い = 吊るした布(8, 2.0, &布の物性::硬い());
    let mut 柔らかい = 吊るした布(8, 2.0, &布の物性::一様に生成する(コンプライアンス::生成する(0.01).unwrap()));
    for _ in 0..30 {
        硬い.一刻み進める(4);
        柔らかい.一刻み進める(4);
    }
    assert!(下端の行の平均y(&柔らかい, 8) < 下端の行の平均y(&硬い, 8) - 0.001);
}

#[test]
fn 床より下へ出た動く粒子は床の高さへ戻る() {
    let mut 参照 = 吊るした布(2, 0.02, &布の物性::硬い());
    参照.一刻み進める(4);
    for 位置 in &参照.位置一覧()[2..] {
        assert!(位置.y().値() >= 0.0);
    }
}
