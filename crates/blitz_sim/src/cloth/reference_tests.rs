//! 布の参照計算の検査: 上端を目標拘束で固定した布が有限のまま垂れること、有限のコンプライアンスが硬い布より伸びること、
//! 床の規則が写されていること、目標拘束の有効と無効が粒子を縛るかどうかを分けることを見る。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, メートル毎秒毎秒, ワールド, 位置, 秒};

use super::colored_constraints::布の彩色済み拘束;
use super::data::布データ;
use super::generate::布を生成する;
use super::material::布の物性;
use super::reference::{布の参照計算, 布の参照計算の条件};
use super::spec::布仕様;
use crate::constraint_graph::{一様な加速度, 添字付き目標拘束, 点添字, 目標拘束のバッチ, 目標拘束の目標};
use crate::xpbd::{コンプライアンス, 刻み幅, 目標拘束の引数};

const 間隔: f32 = 0.05;

fn 条件() -> 布の参照計算の条件 {
    布の参照計算の条件 {
        刻み幅: 刻み幅::生成する(秒::生成する(1.0 / 60.0)).unwrap(),
        重力: 一様な加速度::成分から生成する(
            メートル毎秒毎秒::生成する(0.0),
            メートル毎秒毎秒::生成する(-9.8),
            メートル毎秒毎秒::生成する(0.0),
        ),
        速度減衰: 0.99,
    }
}

/// 上端の行を今の位置へ硬く固定する世界固定点の目標拘束と、追加の目標拘束。
fn 上端行を固定する目標拘束(
    布: &布データ, 追加: Vec<(添字付き目標拘束, 目標拘束の目標)>
) -> 目標拘束のバッチ {
    let mut 一覧: Vec<_> = 布
        .上端行の粒子添字一覧
        .iter()
        .map(|&添字| {
            let 粒子 = 布.粒子一覧[usize::try_from(添字).unwrap()];
            (
                添字付き目標拘束::生成する(点添字::生成する(添字), 目標拘束の引数::硬い()),
                目標拘束の目標::有効な位置(粒子.ワールド位置()),
            )
        })
        .collect();
    一覧.extend(追加);
    目標拘束のバッチ::生成する(布.粒子一覧.len(), 一覧).unwrap()
}

/// 上端の行を固定して原点から垂らした布の参照計算。
fn 吊るした布(
    一辺: u32, 原点y: f32, 物性: &布の物性, 追加の目標拘束: Vec<(添字付き目標拘束, 目標拘束の目標)>
) -> 布の参照計算 {
    let 布 = 布を生成する(&布仕様::生成する(一辺, 間隔, 4.0, [0.0, 原点y, 0.0]).unwrap()).unwrap();
    let 目標 = 上端行を固定する目標拘束(&布, 追加の目標拘束);
    布の参照計算::生成する(&布の彩色済み拘束::生成する(&布, 物性).unwrap(), &目標, 条件()).unwrap()
}

fn 下端の行の平均y(参照: &布の参照計算, 一辺: usize) -> f32 {
    let 一覧 = 参照.位置一覧();
    let 下端 = &一覧[一覧.len() - 一辺..];
    下端.iter().map(|位置| 位置.y().値()).sum::<f32>() / f32::from(u8::try_from(一辺).unwrap())
}

#[test]
fn 上端を固定した硬い布は有限のまま垂れて上端は動かず目標拘束の乗数が反力を観測する() {
    let mut 参照 = 吊るした布(8, 2.0, &布の物性::硬い(), Vec::new());
    let 初期の上端 = 参照.位置一覧()[0];
    for _ in 0..12 {
        参照.一刻み進める(4);
    }
    assert!(
        参照
            .位置一覧()
            .iter()
            .all(|位置| [位置.x(), 位置.y(), 位置.z()].iter().all(|成分| 成分.値().is_finite()))
    );
    assert!((参照.位置一覧()[0] - 初期の上端).長さ().値() < 1.0e-6);
    assert!(参照.拘束違反の二乗平均平方根() < 0.05 * f64::from(間隔));
    assert!(参照.目標拘束のラグランジュ乗数一覧().iter().any(|乗数| 乗数.値() != 0.0));
}

/// 反証: コンプライアンスを写さずに硬い拘束で解くと、柔らかい布も硬い布と同じ垂れになる。
#[test]
fn 有限のコンプライアンスは硬い布より下端が下がる() {
    let mut 硬い = 吊るした布(8, 2.0, &布の物性::硬い(), Vec::new());
    let mut 柔らかい = 吊るした布(8, 2.0, &布の物性::一様に生成する(コンプライアンス::生成する(0.01).unwrap()), Vec::new());
    for _ in 0..30 {
        硬い.一刻み進める(4);
        柔らかい.一刻み進める(4);
    }
    assert!(下端の行の平均y(&柔らかい, 8) < 下端の行の平均y(&硬い, 8) - 0.001);
}

#[test]
fn 床より下へ出た粒子は床の高さへ戻る() {
    let mut 参照 = 吊るした布(2, 0.02, &布の物性::硬い(), Vec::new());
    参照.一刻み進める(4);
    for 位置 in &参照.位置一覧()[2..] {
        assert!(位置.y().値() >= 0.0);
    }
}

/// 反証: 有効と無効を区別せずに射影すると、掴む前の枠が下端の粒子を目標へ引き寄せる。
#[test]
fn 有効な目標拘束は下端の粒子を目標へ寄せ無効なら寄せない() {
    let 目標 = 位置::<ワールド>::生成する(メートル::生成する(0.35), メートル::生成する(2.0), メートル::生成する(0.3));
    let 下端の左端 = 添字付き目標拘束::生成する(点添字::生成する(56), 目標拘束の引数::硬い());
    let mut 有効 = 吊るした布(8, 2.0, &布の物性::硬い(), vec![(下端の左端, 目標拘束の目標::有効な位置(目標))]);
    let mut 無効 = 吊るした布(8, 2.0, &布の物性::硬い(), vec![(下端の左端, 目標拘束の目標::無効な位置(目標))]);
    有効.一刻み進める(4);
    無効.一刻み進める(4);
    assert!((有効.位置一覧()[56] - 目標).長さ().値() < 1.0e-6);
    assert!((無効.位置一覧()[56] - 目標).長さ().値() > 0.1);
    assert_eq!(無効.目標拘束のラグランジュ乗数一覧()[8].値(), 0.0);
}
