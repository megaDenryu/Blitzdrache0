//! 布の参照計算のうち曲げ拘束の検査: 曲げを硬くした布は柔らかい布より曲げの違反(二面角の分布)が小さいこと、曲げのコンプライアンスを変えても
//! 距離拘束の伸びの桁が変わらないこと(伸びと曲げの独立)、曲げ拘束の乗数が反力を観測することを見る。材料は`reference_test_fixtures`が持つ。
//! 垂直に吊るした平らな布は面の内側の力しか受けず平らなままで曲げ拘束が働かないため、水平に敷いた布の縁を固定して垂れ落ちる題材(面の外へ曲がる)で比べる。

#![allow(clippy::unwrap_used)]

use super::material::布の物性;
use super::reference_test_fixtures::{下端の行の平均y, 水平に敷いて縁を固定した布};
use crate::xpbd::{コンプライアンス, 曲げのコンプライアンス};

fn 曲げの物性(曲げ: f32) -> 布の物性 {
    布の物性::生成する(
        コンプライアンス::硬い(),
        コンプライアンス::硬い(),
        曲げのコンプライアンス::生成する(曲げ).unwrap(),
    )
}

/// 反証: 曲げ拘束を距離拘束の反復へ混ぜないと、曲げのコンプライアンスを変えても二面角の分布が変わらない。
#[test]
fn 硬い曲げの布は柔らかい曲げの布より二面角の違反が小さく乗数が反力を観測する() {
    let mut 硬い = 水平に敷いて縁を固定した布(8, 2.0, &曲げの物性(0.0));
    let mut 柔らかい = 水平に敷いて縁を固定した布(8, 2.0, &曲げの物性(1000.0));
    for _ in 0..60 {
        硬い.一刻み進める(4);
        柔らかい.一刻み進める(4);
    }
    let (硬い統計, 柔らかい統計) = (硬い.曲げの違反の統計(), 柔らかい.曲げの違反の統計());
    assert!(
        硬い統計.二乗平均平方根 < 柔らかい統計.二乗平均平方根 * 0.5,
        "硬い{硬い統計:?}に対して柔らかい{柔らかい統計:?}"
    );
    assert!(硬い統計.絶対値の最大 < 柔らかい統計.絶対値の最大);
    // 反復4回の硬い曲げは4キログラムの布を支え切れず(未収束)、下端の高さは両方とも垂直に近い。硬さの読みどころは二面角の分布である。
    assert!((下端の行の平均y(&硬い, 8) - 下端の行の平均y(&柔らかい, 8)).abs() < 0.05);
    assert!(硬い.曲げ拘束のラグランジュ乗数一覧().iter().any(|乗数| 乗数.値() != 0.0));
    assert_eq!(硬い.曲げ拘束のラグランジュ乗数一覧().len(), 7 * 7 + 2 * 7 * 6);
}

/// 反証: 距離のコンプライアンスを倍率で流用して曲げを表すと、曲げを変えたときに伸びの平均も桁で変わる。
#[test]
fn 曲げのコンプライアンスを変えても距離拘束の伸びの桁は変わらない() {
    let mut 伸び一覧 = Vec::new();
    for 曲げ in [0.0f32, 10.0, 1000.0] {
        let mut 参照 = 水平に敷いて縁を固定した布(8, 2.0, &曲げの物性(曲げ));
        for _ in 0..60 {
            参照.一刻み進める(4);
        }
        伸び一覧.push(参照.拘束違反の二乗平均平方根());
    }
    let 最大 = 伸び一覧.iter().copied().fold(f64::MIN, f64::max);
    let 最小 = 伸び一覧.iter().copied().fold(f64::MAX, f64::min);
    assert!(最小 > 0.0 && 最大 / 最小 < 3.0, "伸び一覧{伸び一覧:?}");
}
