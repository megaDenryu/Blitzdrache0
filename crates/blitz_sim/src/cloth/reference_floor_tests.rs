//! 布の参照計算のうち床の規則の検査: 床より下へ出た粒子が床の高さへ戻ること、床の後の目標拘束の最終の成立が床の下の目標へ粒子を戻すことを見る。
//! 材料は`reference_test_fixtures`が持つ。

#![allow(clippy::unwrap_used)]

use super::generate::布を生成する;
use super::material::布の物性;
use super::reference_test_fixtures::{吊るした布, 間隔};
use super::spec::布仕様;
use crate::constraint_graph::{添字付き目標拘束, 点添字, 目標拘束の目標};
use crate::xpbd::目標拘束の引数;

#[test]
fn 床より下へ出た粒子は床の高さへ戻る() {
    let mut 参照 = 吊るした布(2, 0.02, &布の物性::硬い(), Vec::new());
    参照.一刻み進める(4);
    for 位置 in &参照.位置一覧()[2..] {
        assert!(位置.y().値() >= 0.0);
    }
}

/// 反証: 床で止めた後に目標拘束を成立させないと、目標が床の下にある世界固定点の粒子が床の高さに残り、CPUとGPUの位置の差が目標の深さ(0.03メートル)になる。
/// 床は全粒子へ同じ規則を当てるため、目標拘束を持たない下端の粒子は床の高さのままである。
#[test]
fn 床の下に目標を持つ世界固定点の粒子は床で止めた後に目標へ戻る() {
    let 布 = 布を生成する(&布仕様::生成する(2, 間隔, 4.0, [0.0, 0.02, 0.0]).unwrap()).unwrap();
    let 床の下の目標 = 布.粒子一覧[3].ワールド位置();
    assert!(床の下の目標.y().値() < 0.0);
    let 固定点 = 添字付き目標拘束::生成する(点添字::生成する(3), 目標拘束の引数::硬い());
    let mut 参照 = 吊るした布(2, 0.02, &布の物性::硬い(), vec![(固定点, 目標拘束の目標::有効な位置(床の下の目標))]);
    参照.一刻み進める(4);
    assert!((参照.位置一覧()[3] - 床の下の目標).長さ().値() < 1.0e-6);
    assert!(参照.位置一覧()[2].y().値() >= 0.0);
    assert!(参照.目標拘束のラグランジュ乗数一覧()[2].値() != 0.0);
}
