//! 布生成の型付きエラー。

use thiserror::Error;

/// 布仕様の検証・布データ構築で起こりうる失敗。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 布生成エラー {
    #[error("一辺粒子数は2以上でなければならない(指定値: {指定値})")]
    粒子数不足 { 指定値: u32 },

    #[error("一辺粒子数は65535(u16の範囲)を超えられない(指定値: {指定値})")]
    粒子数過大 { 指定値: u32 },

    #[error("粒子間隔は正の値でなければならない(指定値: {指定値})")]
    粒子間隔が非正 { 指定値: f32 },

    #[error("総質量は正の値でなければならない(指定値: {指定値})")]
    総質量が非正 { 指定値: f32 },
}
