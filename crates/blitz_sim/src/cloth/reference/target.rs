//! 布の参照計算のうち目標拘束の状態。触れるのは目標拘束の一覧・一刻みの係数・目標(位置と有効)・乗数だけであり、粒子の位置と逆質量は射影のたびに借りる。
//! GPU(`shaders/cloth_target.slang`)と同じく、距離拘束の色の後ろで目標拘束を並びの順に射影し、有効でない拘束は読まない(乗数も0のまま)。
//! 目標は刻みを跨いで動かさない(参照計算はアタッチと介入を再現しない)。

use blitz_math::{ワールド, 位置, 逆キログラム};

use super::布の参照計算エラー;
use crate::constraint_graph::{添字付き目標拘束, 目標拘束のバッチ, 目標拘束の有効, 目標拘束の目標};
use crate::xpbd::{
    ラグランジュ乗数, 刻み幅, 目標拘束の一刻みの係数, 目標拘束の一回の射影の結果, 距離拘束の参加点
};

pub(super) struct 目標拘束の参照状態 {
    拘束一覧: Vec<添字付き目標拘束>,
    係数一覧: Vec<目標拘束の一刻みの係数>,
    目標一覧: Vec<目標拘束の目標>,
    乗数一覧: Vec<ラグランジュ乗数>,
}

impl 目標拘束の参照状態 {
    /// 刻み幅を受けて全目標拘束の一刻みの係数を1度だけ導く(判断8の工程6)。目標はバッチの初期値である。
    pub(super) fn 生成する(バッチ: &目標拘束のバッチ, 刻み幅: 刻み幅) -> Result<Self, 布の参照計算エラー> {
        let mut 係数一覧 = Vec::with_capacity(バッチ.拘束の数());
        for 拘束 in バッチ.拘束一覧() {
            係数一覧.push(拘束.引数.刻み幅で解く係数を導く(刻み幅)?);
        }
        Ok(Self {
            拘束一覧: バッチ.拘束一覧().to_vec(),
            係数一覧,
            目標一覧: バッチ.初期の目標一覧().to_vec(),
            乗数一覧: vec![ラグランジュ乗数::零(); バッチ.拘束の数()],
        })
    }

    pub(super) fn 乗数を零にする(&mut self) {
        for 乗数 in &mut self.乗数一覧 {
            *乗数 = ラグランジュ乗数::零();
        }
    }

    /// 有効な目標拘束を並びの順に射影し、補正を直ちに粒子の位置へ足す。
    pub(super) fn 逐次に射影する(&mut self, 位置一覧: &mut [位置<ワールド>], 逆質量一覧: &[逆キログラム]) {
        for 添字 in 0..self.拘束一覧.len() {
            let 目標 = self.目標一覧[添字];
            if 目標.有効 == 目標拘束の有効::無効 {
                continue;
            }
            let 粒子 = self.拘束一覧[添字].粒子.配列添字();
            let 参加点 = 距離拘束の参加点::生成する(位置一覧[粒子], 逆質量一覧[粒子]);
            if let 目標拘束の一回の射影の結果::補正した {
                補正,
                更新後のラグランジュ乗数,
            } = self.係数一覧[添字].一回射影する(参加点, 目標.位置, self.乗数一覧[添字])
            {
                self.乗数一覧[添字] = 更新後のラグランジュ乗数;
                位置一覧[粒子] = 位置一覧[粒子].変位を足す(補正);
            }
        }
    }

    pub(super) fn 乗数一覧(&self) -> &[ラグランジュ乗数] {
        &self.乗数一覧
    }
}
