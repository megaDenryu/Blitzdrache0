//! 布の参照計算のうち曲げ拘束の状態。触れるのは彩色の並びの曲げ拘束一覧・一刻みの係数・乗数だけであり、粒子の位置と逆質量は射影のたびに借りる。
//! GPU(`shaders/cloth_bending.slang`)と同じく、距離拘束の色の後ろ・目標拘束の前で曲げ拘束を並びの順に射影する(判断8)。
//! 退化の枝(全て固定・辺や三角形が潰れている)は補正0で乗数を変えない。曲げの違反の統計(曲率の分布)は硬さの記録が読む。

use blitz_math::{ワールド, 位置, 逆キログラム};

use super::布の参照計算エラー;
use crate::constraint_graph::{曲げ拘束の彩色, 添字付き曲げ拘束};
use crate::xpbd::{
    二面角の幾何, 刻み幅, 曲げのラグランジュ乗数, 曲げ拘束の一刻みの係数, 距離拘束の参加点, 面の曲げ拘束の一回の射影の結果
};

/// 曲げ拘束の違反(現在の二面角 − 静止角)の分布。曲率の代理としてラジアンで読む。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 曲げの違反の統計 {
    pub 二乗平均平方根: f64,
    pub 絶対値の平均: f64,
    pub 絶対値の最大: f64,
}

pub(super) struct 曲げ拘束の参照状態 {
    拘束一覧: Vec<添字付き曲げ拘束>,
    係数一覧: Vec<曲げ拘束の一刻みの係数>,
    乗数一覧: Vec<曲げのラグランジュ乗数>,
}

impl 曲げ拘束の参照状態 {
    // 刻み幅を受けて全曲げ拘束の一刻みの係数を1度だけ導く(判断8の工程6)。
    pub(super) fn 生成する(彩色: &曲げ拘束の彩色, 刻み幅: 刻み幅) -> Result<Self, 布の参照計算エラー> {
        let mut 係数一覧 = Vec::with_capacity(彩色.拘束の数());
        for 拘束 in 彩色.拘束一覧() {
            係数一覧.push(拘束.引数.刻み幅で解く係数を導く(刻み幅)?);
        }
        Ok(Self {
            拘束一覧: 彩色.拘束一覧().to_vec(),
            係数一覧,
            乗数一覧: vec![曲げのラグランジュ乗数::零(); 彩色.拘束の数()],
        })
    }

    pub(super) fn 乗数を零にする(&mut self) {
        for 乗数 in &mut self.乗数一覧 {
            *乗数 = 曲げのラグランジュ乗数::零();
        }
    }

    // 曲げ拘束を彩色の並びの順に射影し、補正を直ちに位置へ足す(ガウス・ザイデル型。GPUの色ごとのディスパッチと同じ順序)。
    pub(super) fn 逐次に射影する(&mut self, 位置一覧: &mut [位置<ワールド>], 逆質量一覧: &[逆キログラム]) {
        for 添字 in 0..self.拘束一覧.len() {
            let 点 = self.拘束一覧[添字].点一覧().map(|点| 点.配列添字());
            let 参加点 = 点.map(|点| 距離拘束の参加点::生成する(位置一覧[点], 逆質量一覧[点]));
            if let 面の曲げ拘束の一回の射影の結果::補正した {
                補正a,
                補正b,
                補正c,
                補正d,
                更新後のラグランジュ乗数,
            } = self.係数一覧[添字].面を一回射影する(参加点[0], 参加点[1], 参加点[2], 参加点[3], self.乗数一覧[添字])
            {
                self.乗数一覧[添字] = 更新後のラグランジュ乗数;
                for (点, 補正) in 点.iter().zip([補正a, 補正b, 補正c, 補正d]) {
                    位置一覧[*点] = 位置一覧[*点].変位を足す(補正);
                }
            }
        }
    }

    pub(super) fn 乗数一覧(&self) -> &[曲げのラグランジュ乗数] {
        &self.乗数一覧
    }

    /// 現在の位置での曲げの違反の統計。退化した拘束は違反0と数える。
    pub(super) fn 違反の統計(&self, 位置一覧: &[位置<ワールド>]) -> 曲げの違反の統計 {
        let mut 統計 = 曲げの違反の統計 {
            二乗平均平方根: 0.0,
            絶対値の平均: 0.0,
            絶対値の最大: 0.0,
        };
        for (拘束, 係数) in self.拘束一覧.iter().zip(&self.係数一覧) {
            let 点 = 拘束.点一覧().map(|点| 位置一覧[点.配列添字()]);
            let 違反 = match 二面角の幾何::位置から測る(点[0], 点[1], 点[2], 点[3]) {
                Ok(幾何) => f64::from((幾何.二面角() - 係数.静止角().値()).一周の中で最短の弧へ畳む().値()),
                Err(_) => 0.0,
            };
            統計.二乗平均平方根 += 違反 * 違反;
            統計.絶対値の平均 += 違反.abs();
            統計.絶対値の最大 = 統計.絶対値の最大.max(違反.abs());
        }
        let 本数 = f64::from(u32::try_from(self.拘束一覧.len()).unwrap_or(u32::MAX)).max(1.0);
        統計.二乗平均平方根 = (統計.二乗平均平方根 / 本数).sqrt();
        統計.絶対値の平均 /= 本数;
        統計
    }
}
