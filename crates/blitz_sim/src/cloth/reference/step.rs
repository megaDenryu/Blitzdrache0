//! 布の参照計算の一刻み。GPUの工程(介入→積分→目標の確定→乗数零化→(距離拘束→目標拘束)×反復→(ハッシュ→分離)→仕上げ)のうち、
//! 積分・零化・距離拘束・目標拘束・仕上げを同じ順で再現する。床(y=0)より下へ出た粒子をy=0へ戻すのは`shaders/cloth_finish.slang`と同じ規則である。
//! 固定した粒子を区別する枝は無い。固定は目標拘束が反復の中で行い、積分と床は全粒子へ同じ規則を当てる(判断6)。

use blitz_math::{メートル, ワールド, 位置};

use super::布の参照計算;
use crate::xpbd::{ラグランジュ乗数, 距離拘束の一回の射影の結果, 距離拘束の参加点};

const 床の高さ: メートル = メートル::生成する(0.0);

impl 布の参照計算 {
    /// 1つの物理刻みを進める。
    pub fn 一刻み進める(&mut self, 反復回数: u32) {
        self.積分する();
        for 乗数 in &mut self.乗数一覧 {
            *乗数 = ラグランジュ乗数::零();
        }
        self.目標拘束.乗数を零にする();
        for _ in 0..反復回数 {
            self.色順に逐次に反復する();
            self.目標拘束.逐次に射影する(&mut self.位置一覧, &self.逆質量一覧);
        }
        self.床で止める();
    }

    /// 速度(位置と刻みの開始の位置の差)に減衰を掛け、重力の一刻みの変位を足して位置を進める。
    fn 積分する(&mut self) {
        let 重力の変位 = self.条件.重力.一刻みの変位(self.条件.刻み幅);
        for 添字 in 0..self.位置一覧.len() {
            let 今 = self.位置一覧[添字];
            let 移動 = (今 - self.刻みの開始の位置一覧[添字]).比で伸ばす(self.条件.速度減衰);
            self.刻みの開始の位置一覧[添字] = 今;
            self.位置一覧[添字] = 今.変位を足す(移動 + 重力の変位);
        }
    }

    /// 距離拘束を彩色の並びの順に射影し、補正を直ちに位置へ足す(ガウス・ザイデル型。GPUの色ごとのディスパッチと同じ順序)。
    fn 色順に逐次に反復する(&mut self) {
        for 添字 in 0..self.拘束一覧.len() {
            let 拘束 = self.拘束一覧[添字];
            let a = 距離拘束の参加点::生成する(self.位置一覧[拘束.a.配列添字()], self.逆質量一覧[拘束.a.配列添字()]);
            let b = 距離拘束の参加点::生成する(self.位置一覧[拘束.b.配列添字()], self.逆質量一覧[拘束.b.配列添字()]);
            if let 距離拘束の一回の射影の結果::補正した {
                補正a,
                補正b,
                更新後のラグランジュ乗数,
            } = self.係数一覧[添字].一回射影する(a, b, self.乗数一覧[添字])
            {
                self.乗数一覧[添字] = 更新後のラグランジュ乗数;
                self.位置一覧[拘束.a.配列添字()] = self.位置一覧[拘束.a.配列添字()].変位を足す(補正a);
                self.位置一覧[拘束.b.配列添字()] = self.位置一覧[拘束.b.配列添字()].変位を足す(補正b);
            }
        }
    }

    /// 床より下へ出た粒子を床の高さへ戻す。
    fn 床で止める(&mut self) {
        for 位置 in &mut self.位置一覧 {
            if 位置.y() >= 床の高さ {
                continue;
            }
            *位置 = 位置::<ワールド>::生成する(位置.x(), 床の高さ, 位置.z());
        }
    }
}
