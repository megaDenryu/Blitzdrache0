//! 粒子ごとの隣接拘束リスト生成: GPUのgather方式拘束反復用(判断49追記)。
//! スロット順は[上,下,左,右,左上,右上,左下,右下]で固定(構造4+せん断4)。
//! 参照: 開発スレッド「M9のGPU側実装の詳細設計」。

use super::adjacency_entry::隣接拘束エントリ;
use super::grid_index::線形添字;
use super::index_convert::u32へ;
use super::spec::布仕様;

pub(super) fn 隣接拘束一覧を作る(仕様: &布仕様, 一辺粒子数: usize) -> Vec<[隣接拘束エントリ; 8]> {
    let 間隔 = 仕様.粒子間隔();
    let 斜め静止長 = (間隔 * 間隔 * 2.0).sqrt();

    let mut 全体 = Vec::with_capacity(一辺粒子数 * 一辺粒子数);
    for 行 in 0..一辺粒子数 {
        for 列 in 0..一辺粒子数 {
            全体.push(一粒子分を作る(一辺粒子数, 行, 列, 間隔, 斜め静止長));
        }
    }
    全体
}

fn 一粒子分を作る(
    一辺粒子数: usize, 行: usize, 列: usize, 構造静止長: f32, 斜め静止長: f32
) -> [隣接拘束エントリ; 8] {
    let 上 = (行 > 0).then(|| (行 - 1, 列));
    let 下 = (行 + 1 < 一辺粒子数).then(|| (行 + 1, 列));
    let 左 = (列 > 0).then(|| (行, 列 - 1));
    let 右 = (列 + 1 < 一辺粒子数).then(|| (行, 列 + 1));
    let 左上 = (行 > 0 && 列 > 0).then(|| (行 - 1, 列 - 1));
    let 右上 = (行 > 0 && 列 + 1 < 一辺粒子数).then(|| (行 - 1, 列 + 1));
    let 左下 = (行 + 1 < 一辺粒子数 && 列 > 0).then(|| (行 + 1, 列 - 1));
    let 右下 = (行 + 1 < 一辺粒子数 && 列 + 1 < 一辺粒子数).then(|| (行 + 1, 列 + 1));

    let 候補一覧 = [
        (上, 構造静止長),
        (下, 構造静止長),
        (左, 構造静止長),
        (右, 構造静止長),
        (左上, 斜め静止長),
        (右上, 斜め静止長),
        (左下, 斜め静止長),
        (右下, 斜め静止長),
    ];

    std::array::from_fn(|添字| {
        let (座標, 静止長) = 候補一覧[添字];
        match 座標 {
            Some((r, c)) => 隣接拘束エントリ {
                相手粒子添字: u32へ(線形添字(一辺粒子数, r, c)),
                静止長,
            },
            None => 隣接拘束エントリ::空き(),
        }
    })
}
