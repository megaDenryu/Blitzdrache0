//! 布の彩色済み拘束の検査: 種類ごとのコンプライアンスが拘束へ写ること、色の区間が全拘束を覆い同じ色の中で粒子を共有しないこと、
//! 現在の布の格子(一辺32)の色の数が距離9・曲げ15であること(`_doc/計測/XPBD並列方式_2026-09-02.md`・`_doc/計測/布の曲げ拘束_2026-09-02.md`の実測と同じ)を見る。

#![allow(clippy::unwrap_used)]

use std::collections::BTreeSet;

use super::colored_constraints::布の彩色済み拘束;
use super::generate::布を生成する;
use super::material::布の物性;
use super::spec::布仕様;
use crate::xpbd::{コンプライアンス, 曲げのコンプライアンス};

fn 彩色済み(一辺粒子数: u32, 物性: &布の物性) -> 布の彩色済み拘束 {
    let 布 = 布を生成する(&布仕様::生成する(一辺粒子数, 0.05, 4.0, [0.0, 1.0, 0.0]).unwrap()).unwrap();
    布の彩色済み拘束::生成する(&布, 物性).unwrap()
}

/// 反証: 種類を見ずに1つのコンプライアンスを写すと、構造とせん断で別の硬さを与えた指定が黙って同じ硬さになる。
#[test]
fn 構造とせん断の拘束がそれぞれの種類のコンプライアンスを持つ() {
    let 構造 = コンプライアンス::生成する(0.001).unwrap();
    let せん断 = コンプライアンス::生成する(0.002).unwrap();
    let 拘束 = 彩色済み(4, &布の物性::生成する(構造, せん断, 曲げのコンプライアンス::硬い()));
    for 拘束 in 拘束.拘束グラフ().拘束一覧() {
        let 斜めか = 拘束.引数.静止長.値().値() > 0.06;
        assert_eq!(拘束.引数.コンプライアンス, if 斜めか { せん断 } else { 構造 });
    }
}

#[test]
fn 色の区間は全拘束を覆い同じ色の中で粒子を共有しない() {
    let 拘束 = 彩色済み(8, &布の物性::硬い());
    let 一覧 = 拘束.拘束グラフ().拘束一覧();
    let 合計: u32 = 拘束.色の区間一覧().iter().map(|区間| 区間.本数).sum();
    assert_eq!(usize::try_from(合計).unwrap(), 拘束.拘束の数());
    for 区間 in 拘束.色の区間一覧() {
        let 開始 = 区間.開始.配列添字();
        let mut 触った点 = BTreeSet::new();
        for 拘束 in &一覧[開始..開始 + usize::try_from(区間.本数).unwrap()] {
            assert!(触った点.insert(拘束.a) && 触った点.insert(拘束.b));
        }
    }
}

/// 現在の布(一辺32)の色は距離拘束が9、曲げ拘束が15であり、これがGPUの拘束の工程を1刻みに(9 + 15)×反復回数だけ積む根拠である。
#[test]
fn 一辺32の格子の色の数は距離が9で曲げが15である() {
    let 拘束 = 彩色済み(32, &布の物性::硬い());
    assert_eq!(拘束.色の区間一覧().len(), 9);
    assert_eq!(拘束.曲げ拘束の彩色().色の数(), 15);
    assert_eq!(拘束.曲げ拘束の彩色().拘束の数(), 31 * 31 + 2 * 31 * 30);
}

/// 平らな格子から写した曲げ拘束の静止角は0であり、物性の曲げのコンプライアンスを持つ。
#[test]
fn 曲げ拘束は静止角零と物性の曲げのコンプライアンスを持ち同じ色の中で粒子を共有しない() {
    let 曲げ = 曲げのコンプライアンス::生成する(3.0).unwrap();
    let 拘束 = 彩色済み(8, &布の物性::生成する(コンプライアンス::硬い(), コンプライアンス::硬い(), 曲げ));
    let 彩色 = 拘束.曲げ拘束の彩色();
    let 合計: u32 = 彩色.色の区間一覧().iter().map(|区間| 区間.本数).sum();
    assert_eq!(usize::try_from(合計).unwrap(), 彩色.拘束の数());
    for 拘束 in 彩色.拘束一覧() {
        assert_eq!(拘束.引数.静止角.値().値(), 0.0);
        assert_eq!(拘束.引数.コンプライアンス, 曲げ);
    }
    for 区間 in 彩色.色の区間一覧() {
        let 開始 = 区間.開始.配列添字();
        let mut 触った点 = BTreeSet::new();
        for 拘束 in &彩色.拘束一覧()[開始..開始 + usize::try_from(区間.本数).unwrap()] {
            assert!(拘束.点一覧().iter().all(|点| 触った点.insert(*点)));
        }
    }
}
