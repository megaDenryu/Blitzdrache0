//! 距離拘束: 2粒子間の静止距離を保つ拘束(構造+せん断。曲げ拘束は対象外。判断52)。
//! 種類を持つのは、構造とせん断で別のコンプライアンスを持てるようにするためである(Issue #36「物性」)。
//! コンプライアンスそのものは`布の物性`が種類ごとに1つ持ち、拘束の1本1本には写さない。

/// 構造は縦横の隣接、せん断は斜めの隣接を結ぶ拘束である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 距離拘束の種類 {
    構造,
    せん断,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 距離拘束 {
    pub 粒子a添字: u32,
    pub 粒子b添字: u32,
    pub 静止長: f32,
    pub 種類: 距離拘束の種類,
}
