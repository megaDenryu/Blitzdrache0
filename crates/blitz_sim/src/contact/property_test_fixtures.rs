//! 接触物性の試験が共有する材質の見本と組み立ての手順。混合の性質を見る試験と、組み立ての拒否を見る試験の両方が同じ
//! 材質の並びを読むため、見本をここへ1つだけ置く。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断15: 接触物性は両表面の物性から混合則で決め、既定則と材質対の上書き表を持つ」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::contact_property::接触物性;
use super::friction_coefficient::摩擦係数;
use super::material_id::材質の識別子;
use super::mixing_rule::混合則;
use super::mixing_rule_builder::混合則の組み立て;
use super::restitution_coefficient::反発係数;
use super::surface_property::表面物性;

// 材質の見本。番号・静止摩擦・動摩擦・反発の順で、木(0.6/0.4/0.2)・氷(0.05/0.02/0.1)・ゴム(1.2/1.0/0.9)を表す。
pub(super) const 見本一覧: [(u32, f32, f32, f32); 3] = [(0, 0.6, 0.4, 0.2), (1, 0.05, 0.02, 0.1), (2, 1.2, 1.0, 0.9)];

pub(super) fn 表面物性を作る(静止: f32, 動: f32, 反発: f32) -> 表面物性 {
    表面物性::生成する(
        摩擦係数::生成する(静止).unwrap(),
        摩擦係数::生成する(動).unwrap(),
        反発係数::生成する(反発).unwrap(),
    )
    .unwrap()
}

pub(super) fn 接触物性を作る(静止: f32, 動: f32, 反発: f32) -> 接触物性 {
    接触物性::生成する(
        摩擦係数::生成する(静止).unwrap(),
        摩擦係数::生成する(動).unwrap(),
        反発係数::生成する(反発).unwrap(),
    )
    .unwrap()
}

pub(super) fn 見本を登録した組み立てを作る() -> 混合則の組み立て {
    let mut 組み立て = 混合則の組み立て::生成する();
    for (番号, 静止, 動, 反発) in 見本一覧 {
        組み立て
            .表面物性を登録する(材質の識別子::生成する(番号), 表面物性を作る(静止, 動, 反発))
            .unwrap();
    }
    組み立て
}

pub(super) fn 見本の混合則を組み立てる() -> 混合則 {
    見本を登録した組み立てを作る().組み立てる().unwrap()
}
