//! 細分の始点と終点の形を包む箱(判断11)。
//! 始点配置と終点配置における直方体の外接箱を、それぞれの大域原点から写して大域座標で畳み合わせる。直方体は
//! 衝突の問い合わせの基準原点(その剛体の粗い位置)に相対な形で受け取り、和を単精度へ畳む経路を通らない(判断3)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断3」「判断11」

use blitz_collision::shape::{任意姿勢の直方体, 大域の軸平行の直方体};
use blitz_math::大域ワールド位置;

/// 大域原点に相対な直方体。直方体の中心はその原点からの相対座標である。2つを別々に運ばないのは、別の原点で組んだ直方体と
/// 組み合わせると外接箱が原点の差だけずれ、その取り違えを署名が止めないためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 大域原点に相対な直方体 {
    直方体: 任意姿勢の直方体,
    大域原点: 大域ワールド位置,
}

impl 大域原点に相対な直方体 {
    pub fn 生成する(直方体: 任意姿勢の直方体, 大域原点: 大域ワールド位置) -> Self {
        Self { 直方体, 大域原点 }
    }

    /// この直方体を包む大域の軸平行の直方体。局所の外接箱を大域原点から写して求める。
    pub fn 大域の外接箱を求める(&self) -> 大域の軸平行の直方体 {
        大域の軸平行の直方体::局所の箱を大域原点から写して求める(
            self.大域原点,
            &self.直方体.外接する軸平行の直方体を求める(),
        )
    }
}

/// 始点と終点の直方体の両方を包む大域の軸平行の直方体を求める。
pub fn 始点と終点を包む大域の箱を求める(
    始点: &大域原点に相対な直方体,
    終点: &大域原点に相対な直方体,
) -> 大域の軸平行の直方体 {
    始点.大域の外接箱を求める().相手を含む箱を求める(&終点.大域の外接箱を求める())
}
