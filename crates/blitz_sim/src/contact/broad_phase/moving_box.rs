//! 細分の始点と終点の形を包む箱(判断11)。
//! 始点配置と終点配置における任意姿勢の直方体の外接箱を大域座標で畳み合わせる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11」

use blitz_collision::shape::{任意姿勢の直方体, 大域の軸平行の直方体};
use blitz_math::大域ワールド位置;

/// 始点と終点の直方体の両方を包む大域の軸平行の直方体を求める。
pub fn 始点と終点を包む大域の箱を求める(
    始点の直方体: &任意姿勢の直方体,
    終点の直方体: &任意姿勢の直方体,
) -> 大域の軸平行の直方体 {
    let 始点の局所箱 = 始点の直方体.外接する軸平行の直方体を求める();
    let 終点の局所箱 = 終点の直方体.外接する軸平行の直方体を求める();
    let 始点の大域箱 = 大域の軸平行の直方体::局所の箱を大域原点から写して求める(大域ワールド位置::原点(), &始点の局所箱);
    let 終点の大域箱 = 大域の軸平行の直方体::局所の箱を大域原点から写して求める(大域ワールド位置::原点(), &終点の局所箱);
    始点の大域箱.相手を含む箱を求める(&終点の大域箱)
}
