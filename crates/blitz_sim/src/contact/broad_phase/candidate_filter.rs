//! 粗い選別の候補の対の絞り込み(判断11・18)。
//! 重なりうる形の対から静的どうし・休止中どうしを除外する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11」「判断18」

use blitz_collision::dynamic_index::重なりうる形の対;

use crate::rigid_body::{剛体の台帳, 剛体の識別子, 剛体エラー, 運動種別};

/// 粗い選別を通過した、剛体2つの昇順の候補対。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 剛体どうしの候補対 {
    小さい方の剛体: 剛体の識別子,
    大きい方の剛体: 剛体の識別子,
}

impl 剛体どうしの候補対 {
    pub fn 生成する(小さい方の剛体: 剛体の識別子, 大きい方の剛体: 剛体の識別子) -> Self {
        debug_assert!(小さい方の剛体 < 大きい方の剛体);
        Self {
            小さい方の剛体,
            大きい方の剛体,
        }
    }

    pub fn 小さい方の剛体(&self) -> 剛体の識別子 {
        self.小さい方の剛体
    }

    pub fn 大きい方の剛体(&self) -> 剛体の識別子 {
        self.大きい方の剛体
    }
}

/// 重なりうる形の対から、静的どうしおよび休止中どうしを除外して候補対を受け皿へ集める。
pub fn 剛体どうしの候補対を絞り込む(
    対一覧: &[重なりうる形の対],
    台帳: &剛体の台帳,
    受け皿: &mut Vec<剛体どうしの候補対>,
) -> Result<(), 剛体エラー> {
    受け皿.clear();
    for 対 in 対一覧 {
        let id_a = 剛体の識別子::空間索引の識別子から写す(対.小さいほうの識別子())?;
        let id_b = 剛体の識別子::空間索引の識別子から写す(対.大きいほうの識別子())?;
        let 剛体a = 台帳.参照する(id_a)?;
        let 剛体b = 台帳.参照する(id_b)?;

        let aは静的 = matches!(剛体a.運動種別(), 運動種別::静的);
        let bは静的 = matches!(剛体b.運動種別(), 運動種別::静的);
        if aは静的 && bは静的 {
            continue;
        }

        let aは休止 = 剛体a.実行状態().休止しているか();
        let bは休止 = 剛体b.実行状態().休止しているか();
        if aは休止 && bは休止 {
            continue;
        }

        受け皿.push(剛体どうしの候補対::生成する(id_a, id_b));
    }
    受け皿.sort_unstable();
    受け皿.dedup();
    Ok(())
}
