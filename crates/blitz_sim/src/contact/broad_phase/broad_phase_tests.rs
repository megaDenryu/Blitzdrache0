//! 粗い選別の単体試験(判断11・18)。

use blitz_collision::dynamic_index::{動く形の空間索引, 箱に持たせるゆとりの幅};
use blitz_collision::shape::{任意姿勢の直方体, 大域の軸平行の直方体, 直方体の軸ごとの半分の長さ};
use blitz_math::{キログラム, クォータニオン, メートル, ローカル, 位置, 大域ワールド位置};

use super::candidate_filter::{剛体どうしの候補対, 剛体どうしの候補対を絞り込む};
use super::moving_box::始点と終点を包む大域の箱を求める;
use crate::rigid_body::{剛体の台帳, 剛体の状態の変更, 姿勢, 質量特性, 運動状態, 運動種別, 配置};

fn 直方体を作る(中心x: f32, 半分の長さ: f32) -> 任意姿勢の直方体 {
    let 中心 = 位置::<ローカル>::生成する(メートル::生成する(中心x), メートル::生成する(0.0), メートル::生成する(0.0));
    let 回転 = クォータニオン::<ローカル, ローカル>::恒等();
    let Ok(半分) = 直方体の軸ごとの半分の長さ::生成する([メートル::生成する(半分の長さ); 3]) else {
        panic!("半分の長さの生成に失敗");
    };
    let Ok(直方体) = 任意姿勢の直方体::生成する(中心, 回転, 半分) else {
        panic!("直方体の生成に失敗");
    };
    直方体
}

fn 配置を作る(x: f32) -> 配置 {
    配置::生成する(
        blitz_math::位置::生成する(メートル::生成する(x), メートル::生成する(0.0), メートル::生成する(0.0)),
        姿勢::恒等(),
    )
}

fn 単位質量() -> 質量特性 {
    let Ok(質量) = キログラム::生成する(1.0) else {
        panic!("質量の生成に失敗");
    };
    let Ok(特性) = 質量特性::一様な球(質量, メートル::生成する(0.5)) else {
        panic!("質量特性の生成に失敗");
    };
    特性
}

#[test]
fn 始点と終点を包む大域の箱は両方の端を含む() {
    let 始点 = 直方体を作る(0.0, 1.0);
    let 終点 = 直方体を作る(10.0, 1.0);
    let 箱 = 始点と終点を包む大域の箱を求める(&始点, &終点);
    let 最小 = 箱.最小の端();
    let 最大 = 箱.最大の端();
    assert!(最小.x().値() <= -1.0);
    assert!(最大.x().値() >= 11.0);
}

#[test]
fn 静的どうしと休止中どうしの対は除外される() {
    let mut 台帳 = 剛体の台帳::空();
    let Ok(動的0) = 台帳.登録する(配置を作る(0.0), 単位質量(), 運動種別::動的で始める(運動状態::静止())) else {
        panic!();
    };
    let Ok(動的1) = 台帳.登録する(配置を作る(0.5), 単位質量(), 運動種別::動的で始める(運動状態::静止())) else {
        panic!();
    };
    let Ok(静的2) = 台帳.登録する(配置を作る(0.8), 単位質量(), 運動種別::静的) else {
        panic!();
    };
    let Ok(静的3) = 台帳.登録する(配置を作る(1.0), 単位質量(), 運動種別::静的) else {
        panic!();
    };

    let mut 索引 = 動く形の空間索引::ゆとりの幅から生成する(箱に持たせるゆとりの幅::人型と家具の大きさに見合う既定の幅());
    for &id in &[動的0, 動的1, 静的2, 静的3] {
        let Ok(剛体) = 台帳.参照する(id) else {
            panic!();
        };
        let 形 = 直方体を作る(剛体.配置().重心の位置().x().値(), 0.5);
        let 局所箱 = 形.外接する軸平行の直方体を求める();
        let 大域箱 = 大域の軸平行の直方体::局所の箱を大域原点から写して求める(大域ワールド位置::原点(), &局所箱);
        let Ok(()) = 索引.形を1つ登録する(id.空間索引の識別子へ写す(), &大域箱) else {
            panic!();
        };
    }

    let mut 対一覧 = Vec::new();
    let Ok(()) = 索引.重なりうる形の対を集める(&mut 対一覧) else {
        panic!();
    };

    let mut 候補 = Vec::new();
    let Ok(()) = 剛体どうしの候補対を絞り込む(&対一覧, &台帳, &mut 候補) else {
        panic!();
    };
    // 静的2と静的3の対は除外される
    assert!(!候補.contains(&剛体どうしの候補対::生成する(静的2, 静的3)));
    // 動的0と動的1、動的0と静的2などは残る
    assert!(候補.contains(&剛体どうしの候補対::生成する(動的0, 動的1)));

    // 動的0と動的1を休止させる
    let Ok(b0) = 台帳.書き換える(動的0) else {
        panic!();
    };
    b0.状態を変更する(剛体の状態の変更::休止させる);
    let Ok(b1) = 台帳.書き換える(動的1) else {
        panic!();
    };
    b1.状態を変更する(剛体の状態の変更::休止させる);
    let Ok(()) = 剛体どうしの候補対を絞り込む(&対一覧, &台帳, &mut 候補) else {
        panic!();
    };
    // 動的0と動的1は両方休止しているので除外される
    assert!(!候補.contains(&剛体どうしの候補対::生成する(動的0, 動的1)));
}
