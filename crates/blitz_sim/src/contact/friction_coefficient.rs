//! 摩擦係数: 接線方向の抵抗の限界を法線反力に対する比で表す無次元の量(判断15)。静止と動の区別は表面物性の欄の名前が担い、
//! 値の型は1つである(どちらも同じ値域を持ち、同じ既定則で混ざるため)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断15: 接触物性は両表面の物性から混合則で決め、既定則と材質対の上書き表を持つ」

use super::property_error::接触物性エラー;
use crate::xpbd::ラグランジュ乗数;

/// 0以上の有限の無次元量。上限は置かない(1を超える摩擦は実在する)。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 摩擦係数(f32);

impl 摩擦係数 {
    /// 負と非有限を型付きエラーで拒む。0は摩擦の無い表面として許す。
    pub fn 生成する(値: f32) -> Result<Self, 接触物性エラー> {
        if !値.is_finite() || 値 < 0.0 {
            return Err(接触物性エラー::摩擦係数が値域の外 { 値 });
        }
        Ok(Self(値))
    }

    /// 摩擦の無い表面。
    pub fn 零() -> Self {
        Self(0.0)
    }

    /// 既定則が2つの表面の摩擦を混ぜる規則である相乗平均 √(μ₁ μ₂)。0との混合が0になり、引数の順で結果が変わらない。
    pub fn 相乗平均を求める(self, 相手: Self) -> Self {
        Self((self.0 * 相手.0).sqrt())
    }

    /// 法線のラグランジュ乗数へこの係数を掛けた接線の乗数の限界 μ λ_n。静止摩擦のクーロン円錐の半径(判断13)と、
    /// 動摩擦の衝撃の上限の材料(判断14)がこの1つの式である。
    pub fn 法線の乗数へ掛けた接線の乗数の限界(
        &self, 法線のラグランジュ乗数: ラグランジュ乗数
    ) -> ラグランジュ乗数 {
        法線のラグランジュ乗数.比で伸ばす(self.0)
    }

    /// 境界向けの生値取り出し。ドメインAPI内部では使わない。
    pub fn 値(&self) -> f32 {
        self.0
    }
}
