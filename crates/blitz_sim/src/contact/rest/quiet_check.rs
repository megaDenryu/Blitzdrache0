//! 接触島の静穏の判定(判断18)。接触島のメソッドとして置く。
//! 判断18の4条件は、島の全部の動的剛体について |v| <= v_休止 かつ |ω| <= ω_休止 かつ その剛体の全接触の貫通が接触余白以下 かつ
//! 静止摩擦の錨が置き直されていないことである。4つ目を落とすと、錨を置き直した細分(接触が始まった細分と円錐を超えた細分)を
//! 静穏と数えることになり、まだ動いている島が休止する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::contact_thresholds::休止と判定する接触余白;
use crate::contact::island::接触島;
use crate::rigid_body::剛体;

impl 接触島 {
    /// この島がこの細分で静穏(速度・角速度・貫通残差・錨の置き直しなし)であるかを判定する。
    pub fn 静穏か(&self, バッチ: &接触拘束の二つのバッチ, 剛体一覧: &[剛体]) -> bool {
        for &識別子 in self.含まれる動的剛体() {
            let Some(剛体) = 剛体一覧.get(識別子.配列添字()) else {
                return false;
            };
            if !剛体.運動が静穏か() {
                return false;
            }
        }
        let 接触余白 = 休止と判定する接触余白().値();
        for 拘束 in self
            .剛体と静的世界の接触拘束の区間()
            .スライスを切り出す(バッチ.剛体と静的世界の接触拘束())
        {
            if 拘束.静止摩擦の解の状態().滑走中か() || 拘束.静止摩擦の解の状態().錨を置き直したか() {
                return false;
            }
            let Some(剛体) = 剛体一覧.get(拘束.引数().剛体.配列添字()) else {
                return false;
            };
            let 点a = 剛体.配置().局所点の世界位置(拘束.引数().剛体側の局所接触点);
            let 隔たり = (拘束.引数().静的世界側の接触点 - 点a).方向に沿う長さ(拘束.引数().接触法線).値();
            if -隔たり > 接触余白 {
                return false;
            }
        }
        for 拘束 in self.剛体どうしの接触拘束の区間().スライスを切り出す(バッチ.剛体どうしの接触拘束()) {
            if 拘束.静止摩擦の解の状態().滑走中か() || 拘束.静止摩擦の解の状態().錨を置き直したか() {
                return false;
            }
            let 鍵 = 拘束.履歴の鍵();
            let (Some(剛体a), Some(剛体b)) = (剛体一覧.get(鍵.小さい方の剛体().配列添字()), 剛体一覧.get(鍵.大きい方の剛体().配列添字()))
            else {
                return false;
            };
            let 点a = 剛体a.配置().局所点の世界位置(拘束.引数().局所接触点a);
            let 点b = 剛体b.配置().局所点の世界位置(拘束.引数().局所接触点b);
            let 隔たり = (点b - 点a).方向に沿う長さ(拘束.引数().接触法線).値();
            if -隔たり > 接触余白 {
                return false;
            }
        }
        true
    }
}
