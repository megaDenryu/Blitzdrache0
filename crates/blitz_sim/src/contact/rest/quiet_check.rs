//! 剛体と接触島の静穏判定(判断18)。
//! |v| <= 0.01 m/s かつ |ω| <= 0.05 rad/s かつ 全接触の貫通 <= 接触余白0.005m かつ 錨の置き直しなし。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::contact_thresholds::{
    休止と判定する並進速度の閾値, 休止と判定する接触余白, 休止と判定する角速度の閾値
};
use crate::contact::island::接触島;
use crate::rigid_body::剛体;

/// 剛体の並進速度と角速度が休止の閾値以下であるか。
pub fn 剛体の運動が静穏か(剛体: &剛体) -> bool {
    let Ok(速度) = 剛体.速度() else {
        return true;
    };
    let 並進速さ = 速度.並進速度().長さ().値();
    let 角速さ = 速度.角速度().長さ().値();
    並進速さ <= 休止と判定する並進速度の閾値().値() && 角速さ <= 休止と判定する角速度の閾値().値()
}

/// 接触島がこの細分で静穏(速度・角速度・貫通残差・錨の非滑走)であるかを判定する。
pub fn 島が静穏か(島: &接触島, バッチ: &接触拘束の二つのバッチ, 剛体一覧: &[剛体]) -> bool {
    for &識別子 in 島.含まれる動的剛体() {
        let Some(剛体) = 剛体一覧.get(識別子.配列添字()) else {
            return false;
        };
        if !剛体の運動が静穏か(剛体) {
            return false;
        }
    }
    let 接触余白 = 休止と判定する接触余白().値();
    let 静的拘束一覧 = 島.剛体と静的世界の接触拘束の区間().スライスを切り出す(バッチ.剛体と静的世界の接触拘束());
    for 拘束 in 静的拘束一覧 {
        if 拘束.静止摩擦の解の状態().滑走中か() {
            return false;
        }
        let Some(剛体) = 剛体一覧.get(拘束.引数().剛体.配列添字()) else {
            return false;
        };
        let 点a = 剛体.配置().局所点の世界位置(拘束.引数().剛体側の局所接触点);
        let 点b = 拘束.引数().静的世界側の接触点;
        let 隔たり = (点b - 点a).方向に沿う長さ(拘束.引数().接触法線).値();
        let 食い込み = -隔たり;
        if 食い込み > 接触余白 {
            return false;
        }
    }
    let 剛体間拘束一覧 = 島.剛体どうしの接触拘束の区間().スライスを切り出す(バッチ.剛体どうしの接触拘束());
    for 拘束 in 剛体間拘束一覧 {
        if 拘束.静止摩擦の解の状態().滑走中か() {
            return false;
        }
        let 鍵 = 拘束.履歴の鍵();
        let Some(剛体a) = 剛体一覧.get(鍵.小さい方の剛体().配列添字()) else {
            return false;
        };
        let Some(剛体b) = 剛体一覧.get(鍵.大きい方の剛体().配列添字()) else {
            return false;
        };
        let 点a = 剛体a.配置().局所点の世界位置(拘束.引数().局所接触点a);
        let 点b = 剛体b.配置().局所点の世界位置(拘束.引数().局所接触点b);
        let 隔たり = (点b - 点a).方向に沿う長さ(拘束.引数().接触法線).値();
        let 食い込み = -隔たり;
        if 食い込み > 接触余白 {
            return false;
        }
    }
    true
}
