//! 再開の条件「新しい接触」で島を起こす工程(判断18)。
//! 直前の細分の島の分割を主語に置くのは、休止した島の形をその分割だけが持っており、起こす単位が島だからである。
//! 触れるのは剛体の実行状態と静穏の連続細分数だけであり、接触拘束のバッチは読むだけである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::island::直前の細分の接触島の一覧;
use crate::rigid_body::{休止から起きた理由, 剛体, 剛体の識別子};

impl 直前の細分の接触島の一覧 {
    /// この細分で作った剛体どうしの接触点集合を読み、休止している剛体が動く相手と接触していたら、その剛体を含む島を丸ごと起こす。
    /// 起こした剛体はこの細分のうちに起きた状態へ変わるため、同じ島の残りの接触点は二度目の起床を起こさない。
    pub fn 新しい接触の契機を島へ伝える(&self, バッチ: &接触拘束の二つのバッチ, 剛体一覧: &mut [剛体]) {
        for 拘束 in バッチ.剛体どうしの接触拘束() {
            let 鍵 = 拘束.履歴の鍵();
            let (小さい方, 大きい方) = (鍵.小さい方の剛体(), 鍵.大きい方の剛体());
            self.休止している側を島ごと起こす(小さい方, 大きい方, 剛体一覧);
            self.休止している側を島ごと起こす(大きい方, 小さい方, 剛体一覧);
        }
    }

    fn 休止している側を島ごと起こす(&self, 起こす側: 剛体の識別子, 相手: 剛体の識別子, 剛体一覧: &mut [剛体]) {
        let 休止しているか = 剛体一覧.get(起こす側.配列添字()).is_some_and(|剛体| 剛体.実行状態().休止しているか());
        let 相手が動くか = 剛体一覧.get(相手.配列添字()).is_some_and(剛体::休止した相手を起こす動きを持つか);
        if 休止しているか && 相手が動くか {
            self.契機を受けて島ごと起こす(起こす側, 休止から起きた理由::新しい接触, 剛体一覧);
        }
    }
}
