//! 剛体1つの側から見た休止の判定と再開(判断18)。
//! 島の側(`island_rest`・`quiet_check`)と分けているのは、こちらが剛体1つだけで決まる述語と操作だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use crate::contact::contact_thresholds::{休止と判定する並進速度の閾値, 休止と判定する角速度の閾値};
use crate::rigid_body::{休止から起きた理由, 剛体, 剛体の状態の変更, 剛体の識別子};

impl 剛体 {
    /// 並進速度と角速度がどちらも休止の閾値以下であるか。速度を持たない静的な剛体は動かないため静穏とみなす。
    pub fn 運動が静穏か(&self) -> bool {
        let Ok(速度) = self.速度() else {
            return true;
        };
        速度.並進速度().長さ() <= 休止と判定する並進速度の閾値() && 速度.角速度().長さ() <= 休止と判定する角速度の閾値()
    }
}

/// 識別子で指した剛体を1つ起こし、起きた理由をその剛体へ記録する。
/// 島でなく1つの剛体を起こす経路は、作用の投入と運動種別の遷移と新しい接触の3つが読む。
pub fn 剛体を起こす(識別子: 剛体の識別子, 剛体一覧: &mut [剛体], 理由: 休止から起きた理由) {
    if let Some(剛体) = 剛体一覧.get_mut(識別子.配列添字()) {
        剛体.状態を変更する(剛体の状態の変更::起こす { 理由 });
    }
}
