//! 剛体1つの側から見た休止の判定と再開(判断18)。
//! 島の側(`island_rest`・`quiet_check`)と分けているのは、こちらが剛体1つだけで決まる述語と操作だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use crate::contact::contact_thresholds::{休止と判定する並進速度の閾値, 休止と判定する角速度の閾値};
use crate::rigid_body::{休止から起きた理由, 剛体, 剛体の状態の変更, 剛体の識別子, 運動状態, 運動種別};

impl 剛体 {
    /// 並進速度と角速度がどちらも休止の閾値以下であるか。速度を持たない静的な剛体は動かないため静穏とみなす。
    pub fn 運動が静穏か(&self) -> bool {
        let Ok(速度) = self.速度() else {
            return true;
        };
        速度.並進速度().長さ() <= 休止と判定する並進速度の閾値() && 速度.角速度().長さ() <= 休止と判定する角速度の閾値()
    }

    /// 接触した相手が休止していたらその相手を起こす動きを、この剛体が持つか(判断18の再開の条件「新しい接触」)。
    /// 起きている動的剛体と、速度が零でない運動学的剛体だけが持つ。静的な剛体と休止している剛体は持たない。
    /// 静的な剛体を除くのは、床の上で休止した剛体が床との接触点集合を細分ごとに作り直すたびに起きてしまい、休止が成立しないためである。
    pub fn 休止した相手を起こす動きを持つか(&self) -> bool {
        if !self.実行状態().起きているか() {
            return false;
        }
        match self.運動種別() {
            運動種別::静的 => false,
            運動種別::運動学的 { 運動状態: 速度 } => *速度 != 運動状態::静止(),
            運動種別::動的 { .. } => true,
        }
    }
}

/// 識別子で指した剛体を1つ起こし、起きた理由をその剛体へ記録する。
/// 本番の再開は島を単位に行うため、これを読むのは、直前の細分のどの島にも現れていない剛体を起こす場合だけである(判断18)。
pub(in crate::contact) fn 剛体を起こす(識別子: 剛体の識別子, 剛体一覧: &mut [剛体], 理由: 休止から起きた理由) {
    if let Some(剛体) = 剛体一覧.get_mut(識別子.配列添字()) {
        剛体.状態を変更する(剛体の状態の変更::起こす { 理由 });
    }
}
