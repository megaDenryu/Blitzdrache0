//! 接触島の休止と再開の検査(判断18)。
//! 60細分の静穏継続による休止と、再開条件による島全体の起床を検証する。

use blitz_math::{メートル, ワールド, 位置};

use super::super::contact_batches::接触拘束の二つのバッチ;
use super::super::contact_test_fixtures::台帳へ登録する;
use super::super::contact_thresholds::休止と判定する連続細分数;
use super::super::island::接触島の一覧を構築する;
use crate::rigid_body::{休止から起きた理由, 剛体の台帳, 姿勢, 配置};

fn 位置(x: f32, y: f32, z: f32) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

#[test]
fn 六十細分連続で静穏なら島が休止し再開条件で起きる() {
    let mut 台帳 = 剛体の台帳::空();
    let 箱1 = 台帳へ登録する(&mut 台帳, 配置::生成する(位置(0.0, 0.0, 0.0), 姿勢::恒等()));
    let 箱2 = 台帳へ登録する(&mut 台帳, 配置::生成する(位置(0.0, 1.0, 0.0), 姿勢::恒等()));
    let mut バッチ = 接触拘束の二つのバッチ::積み終えた一覧から組む(vec![], vec![], vec![], vec![]);
    let 島一覧 = 接触島の一覧を構築する(&[箱1, 箱2], &mut バッチ);
    assert_eq!(島一覧.len(), 2);
    let 島 = &島一覧[0];

    assert!(島.静穏か(&バッチ, 台帳.剛体一覧()));

    // 59細分進める
    for _ in 0..(休止と判定する連続細分数 - 1) {
        島.休止状態を更新する(true, 台帳.剛体一覧_mut());
        let Ok(剛体) = 台帳.参照する(箱1) else {
            panic!("剛体の参照に失敗した");
        };
        assert!(剛体.実行状態().起きているか());
    }

    // 60細分目で休止する
    島.休止状態を更新する(true, 台帳.剛体一覧_mut());
    let Ok(剛体) = 台帳.参照する(箱1) else {
        panic!("剛体の参照に失敗した");
    };
    assert!(剛体.実行状態().休止しているか());

    // 再開条件で起こす
    島.起こす(台帳.剛体一覧_mut(), 休止から起きた理由::作用の投入);
    let Ok(剛体_起床) = 台帳.参照する(箱1) else {
        panic!("剛体の参照に失敗した");
    };
    assert!(剛体_起床.実行状態().起きているか());
    assert_eq!(剛体_起床.実行状態().直近に休止から起きた理由(), Some(休止から起きた理由::作用の投入));
}

#[test]
fn 途中で静穏が崩れると連続細分数が零にリセットされる() {
    let mut 台帳 = 剛体の台帳::空();
    let 箱 = 台帳へ登録する(&mut 台帳, 配置::生成する(位置(0.0, 0.0, 0.0), 姿勢::恒等()));
    let mut バッチ = 接触拘束の二つのバッチ::積み終えた一覧から組む(vec![], vec![], vec![], vec![]);
    let 島一覧 = 接触島の一覧を構築する(&[箱], &mut バッチ);
    let 島 = &島一覧[0];

    for _ in 0..30 {
        島.休止状態を更新する(true, 台帳.剛体一覧_mut());
    }
    // 非静穏が発生
    島.休止状態を更新する(false, 台帳.剛体一覧_mut());

    // その後さらに30細分進めても合計30細分なので休止しない
    for _ in 0..30 {
        島.休止状態を更新する(true, 台帳.剛体一覧_mut());
    }
    let Ok(剛体) = 台帳.参照する(箱) else {
        panic!("剛体の参照に失敗した");
    };
    assert!(剛体.実行状態().起きているか());
}
