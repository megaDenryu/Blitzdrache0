//! 接触島の休止と再開の検査(判断18)。
//! 静穏が連続した物理時間が閾値へ達したときの休止と、再開条件による島全体の起床を検証する。
//! 閾値を細分の個数でなく時間で持つため、必要な細分の本数は細分の刻み幅から決まる。

use blitz_math::{メートル, ワールド, 位置, 秒};

use super::super::contact_batches::接触拘束の二つのバッチ;
use super::super::contact_test_fixtures::台帳へ登録する;
use super::super::contact_thresholds::休止と判定する連続静穏の時間;
use super::super::island::{接触島の一覧を構築する, 直前の細分の接触島の一覧};
use crate::rigid_body::{休止から起きた理由, 剛体の台帳, 姿勢, 配置};
use crate::xpbd::刻み幅;

fn 位置(x: f32, y: f32, z: f32) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

// 判断19が確定した細分数16での細分の刻み幅である。
fn 細分の刻み幅() -> 刻み幅 {
    let Ok(幅) = 刻み幅::生成する(秒::生成する(1.0 / 960.0)) else {
        panic!("細分の刻み幅を作れない");
    };
    幅
}

// 閾値の時間へ達するまでに要る細分の本数。刻み幅を積んで数えるのは、実装が積むのと同じ足し算で境目を定めるためである。
fn 休止までに要る細分の本数() -> u32 {
    let 幅 = 細分の刻み幅().秒();
    let mut 積み上げた = 秒::生成する(0.0);
    let mut 本数 = 0;
    while 積み上げた < 休止と判定する連続静穏の時間() {
        積み上げた = 積み上げた + 幅;
        本数 += 1;
    }
    本数
}

#[test]
fn 閾値の物理時間ぶん静穏が続くと島が休止し再開条件で起きる() {
    let mut 台帳 = 剛体の台帳::空();
    let 箱1 = 台帳へ登録する(&mut 台帳, 配置::生成する(位置(0.0, 0.0, 0.0), 姿勢::恒等()));
    let 箱2 = 台帳へ登録する(&mut 台帳, 配置::生成する(位置(0.0, 1.0, 0.0), 姿勢::恒等()));
    let mut バッチ = 接触拘束の二つのバッチ::積み終えた一覧から組む(vec![], vec![], vec![], vec![]);
    let 島一覧 = 接触島の一覧を構築する(&[箱1, 箱2], &mut バッチ, &直前の細分の接触島の一覧::空から始める(), 台帳.剛体一覧());
    assert_eq!(島一覧.len(), 2);
    let 島 = &島一覧[0];

    assert!(島.静穏か(&バッチ, 台帳.剛体一覧()));

    let 本数 = 休止までに要る細分の本数();
    for _ in 0..(本数 - 1) {
        島.休止状態を更新する(true, 細分の刻み幅(), 台帳.剛体一覧_mut());
        let Ok(剛体) = 台帳.参照する(箱1) else {
            panic!("剛体の参照に失敗した");
        };
        assert!(剛体.実行状態().起きているか(), "閾値の時間へ達する前に休止した");
    }

    島.休止状態を更新する(true, 細分の刻み幅(), 台帳.剛体一覧_mut());
    let Ok(剛体) = 台帳.参照する(箱1) else {
        panic!("剛体の参照に失敗した");
    };
    assert!(剛体.実行状態().休止しているか(), "閾値の時間へ達しても休止しない");

    島.起こす(台帳.剛体一覧_mut(), 休止から起きた理由::作用の投入);
    let Ok(剛体_起床) = 台帳.参照する(箱1) else {
        panic!("剛体の参照に失敗した");
    };
    assert!(剛体_起床.実行状態().起きているか());
    assert_eq!(剛体_起床.実行状態().直近に休止から起きた理由(), Some(休止から起きた理由::作用の投入));
}

#[test]
fn 途中で静穏が崩れると静穏の継続時間が零へ戻る() {
    let mut 台帳 = 剛体の台帳::空();
    let 箱 = 台帳へ登録する(&mut 台帳, 配置::生成する(位置(0.0, 0.0, 0.0), 姿勢::恒等()));
    let mut バッチ = 接触拘束の二つのバッチ::積み終えた一覧から組む(vec![], vec![], vec![], vec![]);
    let 島一覧 = 接触島の一覧を構築する(&[箱], &mut バッチ, &直前の細分の接触島の一覧::空から始める(), 台帳.剛体一覧());
    let 島 = &島一覧[0];

    let 半分 = 休止までに要る細分の本数() / 2;
    for _ in 0..半分 {
        島.休止状態を更新する(true, 細分の刻み幅(), 台帳.剛体一覧_mut());
    }
    島.休止状態を更新する(false, 細分の刻み幅(), 台帳.剛体一覧_mut());
    for _ in 0..半分 {
        島.休止状態を更新する(true, 細分の刻み幅(), 台帳.剛体一覧_mut());
    }
    let Ok(剛体) = 台帳.参照する(箱) else {
        panic!("剛体の参照に失敗した");
    };
    assert!(剛体.実行状態().起きているか(), "静穏が途切れたのに継続時間が零へ戻っていない");
}
