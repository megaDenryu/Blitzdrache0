//! 接触島の休止と再開の検査(判断18)。
//! 静穏が連続した細分の本数が閾値へ達したときの休止と、再開条件による島全体の起床を検証する。
//! 閾値の正本は物理時間0.125秒であり、その時間を細分の刻み幅で数えた本数が境目になる。
//! 境目を細分の本数で確かめるのは、閾値に達する直前の細分では休止せず、達した細分で休止することを固定するためである。

use blitz_math::{メートル, ワールド, 位置, 秒};

use super::super::contact_batches::接触拘束の二つのバッチ;
use super::super::contact_test_fixtures::台帳へ登録する;
use super::super::contact_thresholds::休止と判定する連続静穏の細分の本数;
use super::super::island::{接触島の一覧を構築する, 直前の細分の接触島の一覧};
use crate::rigid_body::{
    休止から起きた理由, 剛体の台帳, 剛体の識別子, 姿勢, 実行状態, 配置, 静穏が続いた細分の本数
};
use crate::xpbd::刻み幅;

// 細分数8と16のそれぞれの刻み幅と、閾値0.125秒がその刻み幅で何本に当たるかである。判断19が確定した本番設定は16である。
const 細分数と刻み幅と閾値の本数の一覧: [(u32, f32, u32); 2] = [(8, 1.0 / 480.0, 60), (16, 1.0 / 960.0, 120)];

fn 位置(x: f32, y: f32, z: f32) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

fn 休止の閾値の本数(細分の刻み幅の秒数: f32) -> 静穏が続いた細分の本数 {
    let Ok(幅) = 刻み幅::生成する(秒::生成する(細分の刻み幅の秒数)) else {
        panic!("細分の刻み幅を作れない");
    };
    let Ok(本数) = 休止と判定する連続静穏の細分の本数(幅) else {
        panic!("休止の閾値を細分の本数へ写せない刻み幅である");
    };
    本数
}

#[test]
fn 閾値の本数ぶん静穏が続くと島が休止し再開条件で起きる() {
    for (細分の数, 刻み幅の秒数, 期待する本数) in 細分数と刻み幅と閾値の本数の一覧 {
        let 閾値 = 休止の閾値の本数(刻み幅の秒数);
        assert_eq!(
            閾値.本数(),
            期待する本数,
            "細分数{細分の数}で導いた閾値の本数が正本の物理時間0.125秒と合わない"
        );
        let mut 台帳 = 剛体の台帳::空();
        let 箱1 = 台帳へ登録する(&mut 台帳, 配置::生成する(位置(0.0, 0.0, 0.0), 姿勢::恒等()));
        let 箱2 = 台帳へ登録する(&mut 台帳, 配置::生成する(位置(0.0, 1.0, 0.0), 姿勢::恒等()));
        let mut バッチ = 接触拘束の二つのバッチ::積み終えた一覧から組む(vec![], vec![], vec![], vec![]);
        let 島一覧 = 接触島の一覧を構築する(&[箱1, 箱2], &mut バッチ, &直前の細分の接触島の一覧::空から始める(), 台帳.剛体一覧());
        assert_eq!(島一覧.len(), 2);
        let 島 = &島一覧[0];
        assert!(島.静穏か(&バッチ, 台帳.剛体一覧()));

        for _ in 0..(期待する本数 - 1) {
            島.休止状態を更新する(true, 閾値, 台帳.剛体一覧_mut());
        }
        let 直前 = 箱の実行状態(&台帳, 箱1);
        assert!(
            直前.起きているか(),
            "細分数{細分の数}で閾値の1本手前({}本目)の細分で休止した",
            期待する本数 - 1
        );

        島.休止状態を更新する(true, 閾値, 台帳.剛体一覧_mut());
        assert!(
            箱の実行状態(&台帳, 箱1).休止しているか(),
            "細分数{細分の数}で閾値の{期待する本数}本目の細分で休止しない"
        );

        島.起こす(台帳.剛体一覧_mut(), 休止から起きた理由::作用の投入);
        let 起床後 = 箱の実行状態(&台帳, 箱1);
        assert!(起床後.起きているか());
        assert_eq!(起床後.直近に休止から起きた理由(), Some(休止から起きた理由::作用の投入));
    }
}

#[test]
fn 途中で静穏が崩れると静穏が続いた細分の本数が零へ戻る() {
    let (_, 刻み幅の秒数, 期待する本数) = 細分数と刻み幅と閾値の本数の一覧[1];
    let 閾値 = 休止の閾値の本数(刻み幅の秒数);
    let mut 台帳 = 剛体の台帳::空();
    let 箱 = 台帳へ登録する(&mut 台帳, 配置::生成する(位置(0.0, 0.0, 0.0), 姿勢::恒等()));
    let mut バッチ = 接触拘束の二つのバッチ::積み終えた一覧から組む(vec![], vec![], vec![], vec![]);
    let 島一覧 = 接触島の一覧を構築する(&[箱], &mut バッチ, &直前の細分の接触島の一覧::空から始める(), 台帳.剛体一覧());
    let 島 = &島一覧[0];

    let 半分 = 期待する本数 / 2;
    for _ in 0..半分 {
        島.休止状態を更新する(true, 閾値, 台帳.剛体一覧_mut());
    }
    島.休止状態を更新する(false, 閾値, 台帳.剛体一覧_mut());
    for _ in 0..半分 {
        島.休止状態を更新する(true, 閾値, 台帳.剛体一覧_mut());
    }
    assert!(箱の実行状態(&台帳, 箱).起きているか(), "静穏が途切れたのに本数が零へ戻っていない");
}

fn 箱の実行状態(台帳: &剛体の台帳, 識別子: 剛体の識別子) -> 実行状態 {
    let Ok(剛体) = 台帳.参照する(識別子) else {
        panic!("剛体の参照に失敗した");
    };
    剛体.実行状態()
}
