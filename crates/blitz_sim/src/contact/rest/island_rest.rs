//! 接触島の休止と再開の操作(判断18)。
//! 全剛体が静穏である細分が N_休止 個続いた島を休止させ、6つの再開の条件のいずれかで島全体を起こす。
//! 台帳を丸ごとでなく、島と剛体の一覧だけを受け取る。休止の判定と再開が触れるのは剛体の実行状態と静穏の連続細分数だけであり、
//! 台帳が持つ遷移の予約や登録の口はこの工程の関心ではない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use crate::contact::contact_thresholds::休止と判定する連続細分数;
use crate::contact::island::接触島;
use crate::rigid_body::{休止から起きた理由, 剛体, 剛体の状態の変更, 剛体の識別子, 運動種別};

/// 接触島の休止と再開を司る操作(判断18)。
pub struct 接触島の休止制御;

impl 接触島の休止制御 {
    /// 静穏の判定の結果で島の剛体の連続細分数を進めるか零へ戻し、島の全部が閾値に達したら島を休止させる。
    pub fn 島の休止状態を更新する(島: &接触島, 静穏か: bool, 剛体一覧: &mut [剛体]) {
        if !静穏か {
            Self::島の全部へ変更を配る(島, 剛体一覧, 剛体の状態の変更::静穏の連続細分数を零にする);
            return;
        }
        Self::島の全部へ変更を配る(島, 剛体一覧, 剛体の状態の変更::静穏の連続細分数を進める);
        if Self::島の最小の静穏の連続細分数(島, 剛体一覧) >= 休止と判定する連続細分数 {
            Self::島の全部へ変更を配る(島, 剛体一覧, 剛体の状態の変更::休止させる);
        }
    }

    /// 島全体の動的剛体を起こし、起きた理由をそれぞれの剛体へ記録する。
    pub fn 島を起こす(島: &接触島, 剛体一覧: &mut [剛体], 理由: 休止から起きた理由) {
        Self::島の全部へ変更を配る(島, 剛体一覧, 剛体の状態の変更::起こす { 理由 });
    }

    /// 1つの剛体を起こし、起きた理由をその剛体へ記録する。作用の投入と運動種別の遷移と新しい接触が呼ぶ。
    pub fn 剛体を起こす(識別子: 剛体の識別子, 剛体一覧: &mut [剛体], 理由: 休止から起きた理由) {
        if let Some(剛体) = 剛体一覧.get_mut(識別子.配列添字()) {
            剛体.状態を変更する(剛体の状態の変更::起こす { 理由 });
        }
    }

    fn 島の全部へ変更を配る(島: &接触島, 剛体一覧: &mut [剛体], 変更: 剛体の状態の変更) {
        for &識別子 in 島.含まれる動的剛体() {
            if let Some(剛体) = 剛体一覧.get_mut(識別子.配列添字()) {
                剛体.状態を変更する(変更);
            }
        }
    }

    fn 島の最小の静穏の連続細分数(島: &接触島, 剛体一覧: &[剛体]) -> u32 {
        let mut 最小 = u32::MAX;
        for &識別子 in 島.含まれる動的剛体() {
            let Some(剛体) = 剛体一覧.get(識別子.配列添字()) else {
                continue;
            };
            if let 運動種別::動的 {
                静穏の連続細分数, ..
            } = 剛体.運動種別()
            {
                最小 = 最小.min(静穏の連続細分数.値());
            }
        }
        最小
    }
}
