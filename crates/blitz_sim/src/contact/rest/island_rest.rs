//! 接触島の休止と再開(判断18)。接触島のメソッドとして置く。
//! 台帳を丸ごと受け取らないのは、この工程が触れるのが剛体の実行状態と静穏が続いた細分の本数だけであり、
//! 台帳が持つ登録の口や遷移の予約はこの工程の関心でないためである(判断18の本文の2026-09-04の改訂)。
//! 注意: この更新は細分1本ごとに呼ばれる。刻みの末に1度だけ呼ぶと、閾値の時間が細分数に依って何倍にも伸びる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use crate::contact::island::接触島;
use crate::rigid_body::{休止から起きた理由, 剛体, 剛体の状態の変更, 運動種別, 静穏が続いた細分の本数};

impl 接触島 {
    /// この細分の静穏の判定の結果で島の剛体の静穏が続いた細分の本数を1本進めるか零へ戻し、島の全部が閾値の本数へ達したら島を休止させる。
    /// 既に島の全部が休止しているときに何もしないのは、休止した島の本数を数え続けても意味が無いためである。
    pub fn 休止状態を更新する(&self, 静穏か: bool, 休止の閾値: 静穏が続いた細分の本数, 剛体一覧: &mut [剛体]) {
        if self.全部が休止しているか(剛体一覧) {
            return;
        }
        if !静穏か {
            self.全部へ変更を配る(剛体一覧, 剛体の状態の変更::静穏が続いた細分の本数を零にする);
            return;
        }
        self.全部へ変更を配る(剛体一覧, 剛体の状態の変更::静穏が続いた細分の本数を一本増やす);
        if self.全部の静穏が続いた細分の本数が閾値に達したか(剛体一覧, 休止の閾値) {
            self.全部へ変更を配る(剛体一覧, 剛体の状態の変更::休止させる);
        }
    }

    /// この島の動的剛体を全部起こし、起きた理由をそれぞれの剛体へ記録する。
    pub fn 起こす(&self, 剛体一覧: &mut [剛体], 理由: 休止から起きた理由) {
        self.全部へ変更を配る(剛体一覧, 剛体の状態の変更::起こす { 理由 });
    }

    fn 全部へ変更を配る(&self, 剛体一覧: &mut [剛体], 変更: 剛体の状態の変更) {
        for &識別子 in self.含まれる動的剛体() {
            if let Some(剛体) = 剛体一覧.get_mut(識別子.配列添字()) {
                剛体.状態を変更する(変更);
            }
        }
    }

    fn 全部が休止しているか(&self, 剛体一覧: &[剛体]) -> bool {
        self.含まれる動的剛体()
            .iter()
            .all(|識別子| 剛体一覧.get(識別子.配列添字()).is_some_and(|剛体| 剛体.実行状態().休止しているか()))
    }

    fn 全部の静穏が続いた細分の本数が閾値に達したか(
        &self, 剛体一覧: &[剛体], 閾値: 静穏が続いた細分の本数
    ) -> bool {
        for &識別子 in self.含まれる動的剛体() {
            let Some(剛体) = 剛体一覧.get(識別子.配列添字()) else {
                continue;
            };
            let 運動種別::動的 {
                静穏が続いた細分の本数,
            ..
            } = 剛体.運動種別()
            else {
                continue;
            };
            if !静穏が続いた細分の本数.閾値に達したか(閾値) {
                return false;
            }
        }
        true
    }
}
