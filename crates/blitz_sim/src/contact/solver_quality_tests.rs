//! 接触を解く品質の設定の値域の試験(判断19)。0の回数を型付きエラーで拒むことと、受け取った回数をそのまま返すことを固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」

#![allow(clippy::unwrap_used)]

use super::solver_quality::接触を解く品質の設定;
use super::solver_quality_error::接触を解く品質の設定エラー;

#[test]
fn 回数が零の品質の設定は型付きエラーで拒まれる() {
    assert_eq!(接触を解く品質の設定::生成する(0, 4), Err(接触を解く品質の設定エラー::位置の反復回数が零));
    assert_eq!(
        接触を解く品質の設定::生成する(2, 0),
        Err(接触を解く品質の設定エラー::速度段階の巡回数が零)
    );
}

#[test]
fn 受け取った回数をそのまま返す() {
    let 設定 = 接触を解く品質の設定::生成する(2, 4).unwrap();
    assert_eq!(設定.位置の反復回数(), 2);
    assert_eq!(設定.速度段階の巡回数(), 4);
}
