//! 本番の右辺の側の判定の代わりに置く3つの規則(Issue #103の段階A5の計測10。試験と計器の専用)。
//! 本番の規則(`pseudo_inverse`)は、固有の向きごとに右辺の射影 β_k を、行ごとの許容差 δ_i をその向きへ積み上げた
//! δ_k と比べ、内側の向きを捨てる。δ_i は世界の粗い位置の表現の刻みから導くため、この規則は座標と姿勢に依存する。
//! 段階A5の計測9は、その依存が実害を出すことを測った。緩い坂の回し45度では、固有値が λ_max の 0.415倍という強い
//! 向きの |β_k| が δ_k のすぐ下(余裕1.11倍)へ来るため捨てられ、捨てた成分がそのまま元の行の残差(5.0e-7から5.4e-7)
//! になり、箱はそこで釣り合う。同じ向きは回し0度でも捨てられるが、そちらの |β_k| は120分の1である。
//!
//! ここが持つ3つの規則のうち、前の2つは座標も姿勢も読まない。1つ目は、その向きを解いたときの増分 |β_k| ÷ λ_k が、
//! 右辺をいちばん硬い向きで解いたときに要る増分 ‖b‖ ÷ λ_max より桁違いに大きい向きを捨てる規則である。
//! すなわち解の成分の大きさに上限を置く規則であり、右辺の射影の小ささで捨てる本番の規則とは不等号の向きが逆である。
//! 2つ目は、その向きの増分が行列自身の丸めで
//! 最大の固有値への相対比 λ_k ÷ λ_max が閾値以下の向きを捨てる規則であり、偽の固有値の下限を上げることと同じである。
//! 相対比が小さい向きは、増分が行列の丸めによって
//! 決まっていない向きである。3つ目は本番の判定を置き換えず、条件を足して捨てる本数を減らす規則である。
//! 3つ目が言う「捨てる正当性」とは、最大の固有値への相対比が閾値以下であることか、正規化した増分が倍率以上で
//! あることの、どちらかが成り立つことである。3つ目は本番の判定 |β_k| ≤ δ_k を満たす向きだけを対象にするため、捨てる本数は
//! 本番以下になる。段階A5の計測10は、率だけで捨てる規則が箱10段の塔で無害な向きを282本も新しく捨て、塔が休止
//! しなくなることを測った。3つ目の規則はその害を原理的に持たない。どの規則も、偽の固有値を λ_k ≤ λ_max n ε で
//! 落とす段は本番と同じままである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::discard_reason::擬似逆が固有の向きを捨てた理由;
use super::jacobi_decomposition::対称な連立の固有分解;
use super::pseudo_inverse_solution::擬似逆で解いた増分と捨てた右辺;
use super::法線と接線の連立の行の上限;

/// 本番の右辺の側の判定の代わりに置く規則。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 本番の代わりに置く右辺の向きの捨て方 {
    /// 増分 |β_k| ÷ λ_k が 増分の倍率 × (‖b‖ ÷ λ_max) を超える向きを捨てる(解の成分の大きさに上限を置く)。
    増分が大きい向きを捨てる { 増分の倍率: f32 },
    /// 最大の固有値への相対比 λ_k ÷ λ_max が閾値以下の向きを捨てる(偽の固有値の下限を上げることと同じである)。
    相対固有値が小さい向きを捨てる { 最大の固有値への相対比: f32 },
    /// 本番の判定を満たし、かつ相対固有値が閾値以下か正規化した増分が倍率以上の向きだけを捨てる(本番以下の本数)。
    許容差の内側でありかつ捨てる正当性が在る向きを捨てる {
        最大の固有値への相対比: f32, 増分の倍率: f32
    },
}

impl 対称な連立の固有分解 {
    /// 偽の固有値の向きと、指定の規則が捨てる向きを落とした擬似逆の解。捨てた右辺の返し方は本番と同じである。
    pub(in crate::contact) fn 置き換えた判定で解く(
        &self,
        定数項: &[f32; 法線と接線の連立の行の上限],
        行ごとの解けたと見なす許容差: &[f32; 法線と接線の連立の行の上限],
        偽の固有値の下限: f32,
        捨て方: 本番の代わりに置く右辺の向きの捨て方,
    ) -> 擬似逆で解いた増分と捨てた右辺 {
        let mut 解 = [0.0; 法線と接線の連立の行の上限];
        let mut 捨てた右辺 = [0.0; 法線と接線の連立の行の上限];
        for (k, 固有値) in self.固有値.iter().enumerate().take(self.個数) {
            let 右辺の射影 = self.第k番の向きへの射影(k, 定数項);
            if *固有値 <= 偽の固有値の下限 {
                continue;
            }
            if self.この向きを捨てるか(k, 定数項, 行ごとの解けたと見なす許容差, 捨て方) {
                self.第k番の向きの成分を足し込む(&mut 捨てた右辺, k, 右辺の射影);
                continue;
            }
            self.第k番の向きの成分を足し込む(&mut 解, k, 右辺の射影 / 固有値);
        }
        擬似逆で解いた増分と捨てた右辺::二つの並びから組む(解, 捨てた右辺)
    }

    /// この規則の下で第k番の固有の向きを捨てたかと、捨てたならその理由。捨てた向きの内訳を綴る計器が読む。
    pub(in crate::contact) fn 置き換えた判定で第k番の向きを捨てた理由(
        &self,
        k: usize,
        定数項: &[f32; 法線と接線の連立の行の上限],
        行ごとの解けたと見なす許容差: &[f32; 法線と接線の連立の行の上限],
        偽の固有値の下限: f32,
        捨て方: 本番の代わりに置く右辺の向きの捨て方,
    ) -> 擬似逆が固有の向きを捨てた理由 {
        if self.固有値[k] <= 偽の固有値の下限 {
            return 擬似逆が固有の向きを捨てた理由::偽の固有値;
        }
        if self.この向きを捨てるか(k, 定数項, 行ごとの解けたと見なす許容差, 捨て方) {
            return 擬似逆が固有の向きを捨てた理由::右辺が許容差の内側;
        }
        擬似逆が固有の向きを捨てた理由::捨てていない
    }

    // 第k番の向きを、指定の規則が捨てるか。固有値が正でない向きはこの口へ来ない(偽の固有値の段で落ちる)。
    fn この向きを捨てるか(
        &self,
        k: usize,
        定数項: &[f32; 法線と接線の連立の行の上限],
        行ごとの解けたと見なす許容差: &[f32; 法線と接線の連立の行の上限],
        捨て方: 本番の代わりに置く右辺の向きの捨て方,
    ) -> bool {
        if self.固有値の最大() <= 0.0 {
            return false;
        }
        match 捨て方 {
            本番の代わりに置く右辺の向きの捨て方::増分が大きい向きを捨てる { 増分の倍率 } => {
                self.正規化した増分(k, 定数項) > 増分の倍率
            }
            本番の代わりに置く右辺の向きの捨て方::相対固有値が小さい向きを捨てる { 最大の固有値への相対比 } => {
                self.相対固有値(k) <= 最大の固有値への相対比
            }
            本番の代わりに置く右辺の向きの捨て方::許容差の内側でありかつ捨てる正当性が在る向きを捨てる {
                最大の固有値への相対比,
                増分の倍率,
            } => {
                let 許容差の内側か = self.第k番の向きへの射影(k, 定数項).abs()
                    <= self.第k番の向きへの許容差の射影(k, 行ごとの解けたと見なす許容差);
                let 正当性が在るか = self.相対固有値(k) <= 最大の固有値への相対比
                    || self.正規化した増分(k, 定数項) >= 増分の倍率;
                許容差の内側か && 正当性が在るか
            }
        }
    }

    // 第k番の向きの増分 |β_k| ÷ λ_k を、右辺をいちばん硬い向きで解いたときの増分 ‖b‖ ÷ λ_max で割った値。
    fn 正規化した増分(&self, k: usize, 定数項: &[f32; 法線と接線の連立の行の上限]) -> f32 {
        let 分母 = self.定数項の大きさ(定数項) / self.固有値の最大();
        if 分母 <= 0.0 {
            return 0.0;
        }
        (self.第k番の向きへの射影(k, 定数項) / self.固有値[k]).abs() / 分母
    }

    // 第k番の向きの固有値を最大の固有値で割った相対比 λ_k ÷ λ_max。
    fn 相対固有値(&self, k: usize) -> f32 {
        self.固有値[k] / self.固有値の最大()
    }

    // 右辺のノルム ‖b‖。有効な行の範囲だけを数える。
    fn 定数項の大きさ(&self, 定数項: &[f32; 法線と接線の連立の行の上限]) -> f32 {
        定数項.iter().take(self.個数).map(|値| 値 * 値).sum::<f32>().sqrt()
    }
}
