//! 擬似逆で解いた増分と、許容差の内側と見なして捨てた右辺の成分(判断12・判断13)。
//! 求解の工程(`pseudo_inverse`)から分けているのは、こちらが工程の返す値の形だからである。
//! 捨てた右辺を2つに分けて、許容差の内側として捨てた側だけをこの型が持つ。残差 A Δλ − b は捨てた向きの右辺の
//! 総和であり、その内訳には2つの意味が混ざる。1つは偽の固有値の向きであり、行の数が剛体の自由度を超えた連立で
//! どの乗数でも満たせない成分である(面と面の4点は法線方向に3つの自由度しか持たない)。もう1つは許容差の内側と
//! して捨てた向きであり、こちらは「解けたと見なす」という取り決めで捨てた成分である。
//! 前者を精度の不足として数えてはならない。あちらは配置の表せる細かさではなく連立の階数が決めるものであり、
//! 座標を倍精度にしても消えない。後者だけが取り決めの妥当性の問題であり、行ごとの許容差と比べる対象である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::法線と接線の連立の行の上限;

/// 擬似逆で解いた結果。増分と、許容差の内側として捨てた右辺の行ごとの成分を持つ。
pub(in crate::contact) struct 擬似逆で解いた増分と捨てた右辺 {
    増分: [f32; 法線と接線の連立の行の上限],
    許容差の内側として捨てた右辺: [f32; 法線と接線の連立の行の上限],
}

impl 擬似逆で解いた増分と捨てた右辺 {
    pub(super) fn 二つの並びから組む(
        増分: [f32; 法線と接線の連立の行の上限],
        許容差の内側として捨てた右辺: [f32; 法線と接線の連立の行の上限],
    ) -> Self {
        Self {
            増分,
            許容差の内側として捨てた右辺,
        }
    }

    /// 行ごとの乗数の増分。
    pub(in crate::contact) fn 増分(&self) -> &[f32; 法線と接線の連立の行の上限] {
        &self.増分
    }

    /// 第k行が受け取る、許容差の内側として捨てた右辺の成分。行ごとの許容差と比べる対象である。
    pub(in crate::contact) fn 第k行の許容差の内側として捨てた右辺(&self, k: usize) -> f32 {
        self.許容差の内側として捨てた右辺[k]
    }
}
