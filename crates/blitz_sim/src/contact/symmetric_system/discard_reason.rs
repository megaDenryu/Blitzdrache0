//! 擬似逆が固有の向きを捨てたかと、捨てたならその理由(判断13の原因の分離のための計器が読む型)。
//! 求解(`pseudo_inverse`)から分けているのは、こちらが判定の結果を表す型であり、あちらが判定と求解の工程だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

/// 擬似逆が第k番の固有の向きを捨てたかと、捨てたならその理由。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(in crate::contact) enum 擬似逆が固有の向きを捨てた理由 {
    /// 捨てず、この向きの成分を解へ足した。
    捨てていない,
    /// 固有値が、分解そのものの丸めが作る偽の固有値の下限以下であった。
    偽の固有値,
    /// 右辺のこの向きへの射影が、行ごとの許容差をこの向きへ積み上げた大きさ以下であった。
    右辺が許容差の内側,
}
