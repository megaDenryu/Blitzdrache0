#[cfg(test)]
pub(in crate::contact) use discard_reason::擬似逆が固有の向きを捨てた理由;
pub(in crate::contact) use factorization::対称な連立の分解;
pub(in crate::contact) use jacobi_decomposition::対称な連立の固有分解;

/// 法線と接線を同じ連立へ入れたときの行の上限。接触点1つが法線の行と接線の行を1つずつ持つ。
/// 固有分解の受け皿の大きさがこれであり、法線だけを解く LDLᵀ の側は接触点の上限のままである。
pub(in crate::contact) const 法線と接線の連立の行の上限: usize = 2 * 接触点の上限;

// 特異な連立を避けるために対角へ足す正則化の、行列の規模に対する比。
const 特異を避ける正則化の比: f32 = 1.0e-4;

/// 対角へ足す正則化。大きさは行列の規模(対角の最大)に比例し、質量と腕の取り方に依らない。
/// 増分の左辺だけへ足し、右辺へは足さない(収束の到達点を変えないため)。
pub(in crate::contact) fn 特異を避ける正則化を求める(
    対称行列: &[[f32; 接触点の上限]; 接触点の上限], 個数: usize
) -> f32 {
    特異を避ける正則化の比 * 対角の最大を求める(対称行列, 個数)
}

// 正則化と枢軸の下限が基準にする行列の規模。対角の成分は非負であるため、最大がそのまま規模になる。
fn 対角の最大を求める(対称行列: &[[f32; 接触点の上限]; 接触点の上限], 個数: usize) -> f32 {
    (0..個数).map(|k| 対称行列[k][k]).fold(0.0, f32::max)
}
