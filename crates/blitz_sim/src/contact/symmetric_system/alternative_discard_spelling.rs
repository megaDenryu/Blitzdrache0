//! 本番の代わりに置く右辺の向きの捨て方を、表の見出しへ綴る形(試験と計器の専用)。規則の定義
//! (`alternative_discard_rule`)から分けているのは、こちらが計器の表のためだけの綴りであり、擬似逆の求解が
//! 1度も読まないためである。受理の許容差の当て方も、同じ理由で定義と綴りを別のファイルへ置いている
//! (`normal_tangential_system/tolerance_application/spelling.rs`)。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::alternative_discard_rule::本番の代わりに置く右辺の向きの捨て方;

impl 本番の代わりに置く右辺の向きの捨て方 {
    /// 表の見出しへ綴る形。閾値も綴るのは、同じ規則を閾値だけ振って並べる計器が在るためである。
    pub(in crate::contact) fn 綴り(&self) -> String {
        match *self {
            Self::増分が大きい向きを捨てる { 増分の倍率 } => {
                format!("増分の大きさで捨てる_倍率{増分の倍率}")
            }
            Self::相対固有値が小さい向きを捨てる {
                最大の固有値への相対比
            } => {
                format!("相対固有値が小さい向きを捨てる_相対比{最大の固有値への相対比}")
            }
            Self::許容差の内側でありかつ捨てる正当性が在る向きを捨てる {
                最大の固有値への相対比,
                増分の倍率,
            } => {
                format!("捨てる正当性も見て捨てる_相対比{最大の固有値への相対比}_倍率{増分の倍率}")
            }
        }
    }
}
