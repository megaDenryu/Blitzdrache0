//! 固有分解を使って、捨てる向きを持つ擬似逆で解く工程(判断12・判断13)。
//! 正則化を足して解く形を採らないのは、接線の右辺が点ごとの錨の変位の長さであり、同じ剛体へ複数の点ごとの錨の
//! 拘束を課した材料では、剛体1つの運動で実現できない成分を含むことを実測で確かめたためである。その成分は行列の
//! 小さい固有値の向きに乗る。正則化 ε で解くと、その成分が ε で割られて乗数だけが桁で膨れる(実測で、真の増分
//! 1.5e-5に対して5.2e-3の増分が向かい合う2行へ現れた)。補正そのものは打ち消し合って動かないが、クーロン円錐の
//! 判定が読む接線の乗数の合力が壊れ、保持できる坂で集合が滑走中へ落ちる。
//! 捨てる判定は2つを別々に置く。行列の側は、分解そのものの丸めが作る偽の固有値を λ_k ≤ λ_max n ε で落とす。
//! 右辺の側は、固有の向きごとに β_k = v_kᵀ b と δ_k を比べ、|β_k| ≤ δ_k の向きを落とす。δ_i はその行の右辺を
//! 解けたと見なす許容差であり、行の方向へ射影した世界位置の差の表現の刻みから呼び出し側が導く。
//! 右辺の許容差と行列の分解の誤差を1つの比へ混ぜてはならない。混ぜると、右辺の全体のノルムが小さい連立で、
//! 誤差の無い固有の向きまで一斉に落ちる(世界の原点から遠いだけの場面で解が零になる)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#[cfg(test)]
use super::discard_reason::擬似逆が固有の向きを捨てた理由;
use super::jacobi_decomposition::対称な連立の固有分解;
use super::法線と接線の連立の行の上限;

// 分解そのものの丸めが作る偽の固有値の比。次数 n の対称行列をヤコビ法で分解したときの固有値の誤差の桁が n ε である。
const 次数の上界: f32 = 16.0; // 法線と接線の連立の行の上限と同じ値。整数から実数への縮小変換を避けるために別に置く

impl 対称な連立の固有分解 {
    /// 偽の固有値の向きと、許容差の内側にしかない右辺の向きを捨てた擬似逆の解 Σ_k (v_kᵀ b ÷ λ_k) v_k。
    /// 行ごとの解けたと見なす許容差 δ_i は、その行の方向へ射影した世界位置の差が持つ表現の刻みから決まる。
    pub(in crate::contact) fn 擬似逆で解く(
        &self,
        定数項: &[f32; 法線と接線の連立の行の上限],
        行ごとの解けたと見なす許容差: &[f32; 法線と接線の連立の行の上限],
    ) -> [f32; 法線と接線の連立の行の上限] {
        let 偽の固有値の下限 = self.偽の固有値の下限();
        let mut 解 = [0.0; 法線と接線の連立の行の上限];
        for (k, 固有値) in self.固有値.iter().enumerate().take(self.個数) {
            if *固有値 <= 偽の固有値の下限 {
                continue;
            }
            let 右辺の射影 = self.第k番の向きへの射影(k, 定数項);
            if 右辺の射影.abs() <= self.第k番の向きへの許容差の射影(k, 行ごとの解けたと見なす許容差) {
                continue;
            }
            let 係数 = 右辺の射影 / 固有値;
            for (解の値, 第i行) in 解.iter_mut().zip(self.固有ベクトルの列.iter()).take(self.個数) {
                *解の値 += 係数 * 第i行[k];
            }
        }
        解
    }

    /// 第k番の固有の向きを捨てたかと、捨てたならその理由。捨てた向きの内訳を綴る計器が読む。
    #[cfg(test)]
    pub(in crate::contact) fn 第k番の向きを捨てた理由(
        &self,
        k: usize,
        定数項: &[f32; 法線と接線の連立の行の上限],
        行ごとの解けたと見なす許容差: &[f32; 法線と接線の連立の行の上限],
    ) -> 擬似逆が固有の向きを捨てた理由 {
        if self.固有値[k] <= self.偽の固有値の下限() {
            return 擬似逆が固有の向きを捨てた理由::偽の固有値;
        }
        if self.第k番の向きへの射影(k, 定数項).abs() <= self.第k番の向きへの許容差の射影(k, 行ごとの解けたと見なす許容差)
        {
            return 擬似逆が固有の向きを捨てた理由::右辺が許容差の内側;
        }
        擬似逆が固有の向きを捨てた理由::捨てていない
    }

    // 分解そのものの丸めが作る偽の固有値の下限 λ_max n ε。
    fn 偽の固有値の下限(&self) -> f32 {
        self.固有値の最大() * 次数の上界 * f32::EPSILON
    }

    // 第k番の固有ベクトルへの右辺の射影 β_k = v_kᵀ b。
    fn 第k番の向きへの射影(&self, k: usize, 定数項: &[f32; 法線と接線の連立の行の上限]) -> f32 {
        self.固有ベクトルの列
            .iter()
            .zip(定数項.iter())
            .take(self.個数)
            .map(|(第i行, 定数)| 第i行[k] * 定数)
            .sum()
    }

    // 第k番の固有ベクトルの向きへ行ごとの許容差を積み上げた大きさ δ_k = √(Σ_i (v_ik δ_i)²)。
    // |β_k| がこれ以下の向きは、解けたものとして扱う。
    // 注意: 二乗和の平方根は誤差の上限でも標準偏差の合成でもない。行ごとの誤差が独立な確率変数なら標準偏差の
    // 合成として読めるが、この連立の行は同じ剛体の配置と回転を共有するため誤差は独立でない。採っている理由は
    // 実測である。絶対値の和 Σ_i |v_ik| δ_i にすると、行が8つある連立ではその値が右辺そのものの桁へ達して解ける
    // 向きまで捨てる(坂の正接0.44で接線変位の3割が残り、集合が滑走へ落ちた)。許容差の積み上げ方を変えても
    // 物理の結果が変わらない範囲は`normal_tangential_system/tolerance_tests`が固定する。
    fn 第k番の向きへの許容差の射影(
        &self, k: usize, 行ごとの解けたと見なす許容差: &[f32; 法線と接線の連立の行の上限]
    ) -> f32 {
        self.固有ベクトルの列
            .iter()
            .zip(行ごとの解けたと見なす許容差.iter())
            .take(self.個数)
            .map(|(第i行, 許容差)| (第i行[k] * 許容差) * (第i行[k] * 許容差))
            .sum::<f32>()
            .sqrt()
    }

    fn 固有値の最大(&self) -> f32 {
        (0..self.個数).map(|k| self.固有値[k]).fold(0.0, f32::max)
    }
}
