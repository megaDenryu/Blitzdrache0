//! 対称な連立のヤコビ法による固有分解と、小さい固有値の向きを捨てた擬似逆の求解(判断13)。接線の連立が読む。
//! 正則化を足して解く形をここで採らないのは、接線の右辺が点ごとの錨の変位の長さであり、同じ剛体へ複数の点ごとの
//! 錨の拘束を課した材料では、剛体1つの運動で実現できない成分を含むことを実測で確かめたためである。その成分は
//! 行列の小さい固有値の向きに乗る。正則化 ε で解くと、その成分が ε で割られて乗数だけが桁で膨れる(実測で、
//! 真の増分1.5e-5に対して5.2e-3の増分が向かい合う2行へ現れた)。補正そのものは打ち消し合って動かないが、
//! クーロン円錐の判定が読む接線の乗数の合力が壊れ、保持できる坂で集合が滑走中へ落ちる。
//! 捨てる下限は右辺の丸めから導く。右辺は世界位置の差であり、単精度では座標の大きさに比例する丸めを持つ。
//! その丸め δ を固有値 λ_k で割った誤差が、解の大きさ ‖b‖ ÷ λ_max を超える向きは、解ける運動でなく丸めを解いている。
//! ヤコビ法の回しは行と列の番号の昇順に固定した掃きを決まった回数だけ行うため、同じ入力から同じ解が出る。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_collision::contact_set::接触点の上限;

// 掃きの回数。接触点の上限が8であり、8次の対称行列はこの回数で対角へ十分寄る。
const 掃きの回数: usize = 12;

// 非対角の成分をこれ以下と見なして回さない大きさ。回転の角が定まらない成分を触らないための下限である。
const 回さない非対角の大きさ: f32 = 1.0e-12;

// 分解そのものの丸めが作る偽の固有値の比。次数 n の対称行列をヤコビ法で分解したときの固有値の誤差の桁が n ε である。
const 次数の上界: f32 = 8.0; // 接触点の上限と同じ値。整数から実数への縮小変換を避けるために別に置く

/// 対称な連立の固有分解。固有値と、その固有ベクトルを列に持つ行列である。
pub(in crate::contact) struct 対称な連立の固有分解 {
    固有値: [f32; 接触点の上限],
    固有ベクトルの列: [[f32; 接触点の上限]; 接触点の上限],
    個数: usize,
}

impl 対称な連立の固有分解 {
    /// ヤコビ法で分解する。対称であることは呼び出し側が組み立てで保証する。
    pub(in crate::contact) fn 分解する(対称行列: &[[f32; 接触点の上限]; 接触点の上限], 個数: usize) -> Self {
        let mut 分解 = Self {
            固有値: [0.0; 接触点の上限],
            固有ベクトルの列: [[0.0; 接触点の上限]; 接触点の上限],
            個数,
        };
        let mut 対角へ寄せる行列 = *対称行列;
        for (k, 第k行) in 分解.固有ベクトルの列.iter_mut().enumerate().take(個数) {
            第k行[k] = 1.0;
        }
        for _ in 0..掃きの回数 {
            for p in 0..個数 {
                for q in (p + 1)..個数 {
                    分解.一つの非対角を消す(&mut 対角へ寄せる行列, p, q);
                }
            }
        }
        for (k, 固有値) in 分解.固有値.iter_mut().enumerate().take(個数) {
            *固有値 = 対角へ寄せる行列[k][k];
        }
        分解
    }

    /// 小さい固有値の向きを捨てた擬似逆の解 Σ_k (v_kᵀ b ÷ λ_k) v_k。
    /// 右辺の丸めの大きさは、右辺を作った世界位置の座標の大きさに単精度の機械イプシロンを掛けた長さである。
    pub(in crate::contact) fn 擬似逆で解く(
        &self, 定数項: &[f32; 接触点の上限], 右辺の丸めの大きさ: f32
    ) -> [f32; 接触点の上限] {
        let 下限 = self.捨てる固有値の下限(定数項, 右辺の丸めの大きさ);
        let mut 解 = [0.0; 接触点の上限];
        for (k, 固有値) in self.固有値.iter().enumerate().take(self.個数) {
            if *固有値 <= 下限 {
                continue;
            }
            let mut 内積 = 0.0;
            for (第i行, 定数) in self.固有ベクトルの列.iter().zip(定数項.iter()).take(self.個数) {
                内積 += 第i行[k] * 定数;
            }
            let 係数 = 内積 / 固有値;
            for (解の値, 第i行) in 解.iter_mut().zip(self.固有ベクトルの列.iter()).take(self.個数) {
                *解の値 += 係数 * 第i行[k];
            }
        }
        解
    }

    // 捨てる固有値の下限 λ_max × max(δ ÷ ‖b‖, n ε)。δ ÷ ‖b‖ は右辺の丸めが解へ持ち込む誤差が解の大きさへ達する比であり、
    // n ε は分解そのものの丸めが作る偽の固有値の比である。右辺が零の連立は解が零であるため下限を最大に置く。
    fn 捨てる固有値の下限(&self, 定数項: &[f32; 接触点の上限], 右辺の丸めの大きさ: f32) -> f32 {
        let 二乗和: f32 = (0..self.個数).map(|k| 定数項[k] * 定数項[k]).sum();
        let ノルム = 二乗和.sqrt();
        let 丸めの比 = if ノルム > 0.0 { 右辺の丸めの大きさ / ノルム } else { 1.0 };
        self.固有値の最大() * 丸めの比.max(次数の上界 * f32::EPSILON)
    }

    fn 固有値の最大(&self) -> f32 {
        (0..self.個数).map(|k| self.固有値[k]).fold(0.0, f32::max)
    }

    // 第p行第q列の非対角の成分を消すヤコビ回転。行列と固有ベクトルの列の両方を同じ角で回す。
    fn 一つの非対角を消す(&mut self, 行列: &mut [[f32; 接触点の上限]; 接触点の上限], p: usize, q: usize) {
        if 行列[p][q].abs() < 回さない非対角の大きさ {
            return;
        }
        let 傾き = (行列[q][q] - 行列[p][p]) / (2.0 * 行列[p][q]);
        let 正接 = 傾き.signum() / (傾き.abs() + (傾き * 傾き + 1.0).sqrt());
        let 余弦 = 1.0 / (正接 * 正接 + 1.0).sqrt();
        let 正弦 = 正接 * 余弦;
        let 個数 = self.個数;
        for 第k行 in 行列.iter_mut().take(self.個数) {
            let (左, 右) = (第k行[p], 第k行[q]);
            第k行[p] = 余弦 * 左 - 正弦 * 右;
            第k行[q] = 正弦 * 左 + 余弦 * 右;
        }
        let (第p行, 第q行) = (行列[p], 行列[q]);
        for (k, (左, 右)) in 第p行.iter().zip(第q行.iter()).enumerate().take(self.個数) {
            行列[p][k] = 余弦 * 左 - 正弦 * 右;
            行列[q][k] = 正弦 * 左 + 余弦 * 右;
        }
        for 第k行 in self.固有ベクトルの列.iter_mut().take(個数) {
            let (左, 右) = (第k行[p], 第k行[q]);
            第k行[p] = 余弦 * 左 - 正弦 * 右;
            第k行[q] = 正弦 * 左 + 余弦 * 右;
        }
    }
}
