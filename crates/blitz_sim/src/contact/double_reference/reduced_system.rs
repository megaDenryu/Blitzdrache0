/// 倍精度の、有効集合の行だけを抜き出した対称な連立。
pub(in crate::contact) struct 倍精度の抜き出した連立 {
    pub(in crate::contact) 並び: 倍精度の抜き出した行の並び,
    pub(in crate::contact) 対称行列: [[f64; 法線と接線の連立の行の上限]; 法線と接線の連立の行の上限],
    pub(in crate::contact) 定数項: [f64; 法線と接線の連立の行の上限],
    pub(in crate::contact) 行ごとの解けたと見なす許容差: [f64; 法線と接線の連立の行の上限],
}

impl 倍精度の抜き出した連立 {
    pub(in crate::contact) fn 抜き出す(連立: &倍精度の接触点集合の連立, 有効集合: &倍精度の連立の有効集合) -> Self {
        let 並び = 倍精度の抜き出した行の並び::有効集合から組む(連立, 有効集合);
        let mut 抜き出した = Self {
            対称行列: [[0.0; 法線と接線の連立の行の上限]; 法線と接線の連立の行の上限],
            定数項: [0.0; 法線と接線の連立の行の上限],
            行ごとの解けたと見なす許容差: [0.0; 法線と接線の連立の行の上限],
            並び,
        };
        let 行ごとの勾配 = 抜き出した.行ごとの勾配を読む(連立);
        for (k, 自分) in 行ごとの勾配.iter().enumerate().take(抜き出した.並び.行の数()) {
            let Some(自分) = 自分 else { continue };
            抜き出した.一行の数値を埋める(連立, 有効集合, &行ごとの勾配, k, 自分);
        }
        抜き出した
    }

    /// この連立の固有分解。診断の表が固有値と捨てた理由を読むためにも使う。
    pub(in crate::contact) fn 固有分解する(&self) -> 倍精度の対称な連立の固有分解 {
        倍精度の対称な連立の固有分解::分解する(&self.対称行列, self.並び.行の数())
    }

    /// 擬似逆で解いた行ごとの増分と、許容差の内側として捨てた右辺。
    pub(in crate::contact) fn 解く(&self) -> 倍精度の擬似逆で解いた増分と捨てた右辺 {
        self.固有分解する().擬似逆で解く(&self.定数項, &self.行ごとの解けたと見なす許容差)
    }

    /// 解いた増分を点ごとの増分へ戻す。外した点の法線の乗数は零へ解放する増分になる。
    pub(in crate::contact) fn もとの点へ戻す(
        &self,
        解: &倍精度の擬似逆で解いた増分と捨てた右辺,
        連立: &倍精度の接触点集合の連立,
        有効集合: &倍精度の連立の有効集合,
    ) -> 倍精度の接触点集合の同時解 {
        let 増分 = 解.増分();
        let mut 同時解 = 倍精度の接触点集合の同時解::空();
        let mut 法線の増分 = [0.0; 法線と接線の連立の行の上限];
        let mut 接線の増分 = [0.0; 法線と接線の連立の行の上限];
        for k in 0..self.並び.法線の行の数() {
            法線の増分[self.並び.法線の行のもとの点の番号(k)] = 増分[k];
        }
        for k in 0..self.並び.接線の行の数() {
            接線の増分[self.並び.接線の行のもとの点の番号(k)] = 増分[self.並び.法線の行の数() + k];
        }
        for 点の番号 in 0..連立.点の数() {
            let 有効 = 有効集合.有効か(点の番号);
            let 法線 = if 有効 {
                法線の増分[点の番号]
            } else {
                連立.外した点の法線の乗数を解放する増分(点の番号)
            };
            同時解.一点の解を書き込む(点の番号, 法線, 接線の増分[点の番号], 有効);
        }
        同時解
    }

    // 抜き出した並びの順に読んだ行の勾配。行列の組み立てが行どうしの交差を取るため、先に一覧にする。
    fn 行ごとの勾配を読む(
        &self,
        連立: &倍精度の接触点集合の連立,
    ) -> [Option<倍精度の一行の二つの符号付き勾配>; 法線と接線の連立の行の上限] {
        let mut 勾配 = [None; 法線と接線の連立の行の上限];
        for (k, 一つ) in 勾配.iter_mut().enumerate().take(self.並び.行の数()) {
            *一つ = 連立.持ち主の行の勾配(self.並び.第k行の持ち主(k));
        }
        勾配
    }

    // 第k行の対称行列・定数項・許容差を埋める。定数項からは、外した点の解放がこの行を動かす長さを引く。
    fn 一行の数値を埋める(
        &mut self,
        連立: &倍精度の接触点集合の連立,
        有効集合: &倍精度の連立の有効集合,
        行ごとの勾配: &[Option<倍精度の一行の二つの符号付き勾配>; 法線と接線の連立の行の上限],
        k: usize,
        自分: &倍精度の一行の二つの符号付き勾配,
    ) {
        for (l, 相手) in 行ごとの勾配.iter().enumerate().take(self.並び.行の数()) {
            if let Some(相手) = 相手 {
                self.対称行列[k][l] = 自分.交差の寄与(相手);
            }
        }
        let 持ち主 = self.並び.第k行の持ち主(k);
        self.対称行列[k][k] += 連立.持ち主の行の対角へ足す刻み依存量(持ち主);
        self.定数項[k] = 連立.持ち主の行の右辺(持ち主) - 連立.外した点の解放が動かす長さ(自分, 有効集合);
        self.行ごとの解けたと見なす許容差[k] = 自分.解けたと見なす許容差();
    }
}
