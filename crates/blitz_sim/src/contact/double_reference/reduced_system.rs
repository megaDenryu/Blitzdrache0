//! 倍精度の、有効集合に絞った法線と接線の連立(Issue #59の数値契約の診断)。単精度の`有効な行だけを抜き出した連立`
//! と同じ順で対称行列 J M⁻¹ Jᵀ と右辺と行ごとの許容差を組み、同じ擬似逆で解く。
//! 行列と右辺を公開しているのは、診断の表が固有値の散らばり・右辺の射影・行ごとの残差を単精度の側と並べて
//! 綴るためである。単精度の側は同じ量を計器(`cone_breach_record`)が読む。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

