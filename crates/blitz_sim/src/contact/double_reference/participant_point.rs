//! 倍精度の、接触の射影に参加する1つの点(Issue #59の数値契約の診断)。単精度の`接触の射影に参加する点`が
//! 答える量(世界位置・腕・一般化逆質量の交差の寄与・解けたと見なす許容差・動かせないか)を、同じ式で倍精度で
//! 答える。静的世界の接触相手は逆質量と逆慣性を零にし、点そのものを世界位置に置く。
//! 許容差を倍精度の表現の刻みから導くのは、この参照計算が「座標をいくらでも細かく表せるなら解法が何を返すか」を
//! 答えるためである。単精度の側は同じ式を単精度の刻みで読む。この違いだけが、解法の許容差が物理の判定へ
//! 漏れているかどうかを分ける材料になる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_math::{ローカル, ワールド, 位置, 変位};

use super::inverse_inertia::倍精度のワールドの逆慣性;
use super::placement::倍精度の剛体の配置;
use super::vector::倍精度の三次元ベクトル;
use crate::rigid_body::{質量特性, 配置};

/// 倍精度の接触の射影の片側。世界位置と腕と2つの実効の重みを持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 倍精度の接触の射影に参加する点 {
    世界位置: 倍精度の三次元ベクトル,
    腕: 倍精度の三次元ベクトル,
    逆質量: f64,
    ワールドの逆慣性: 倍精度のワールドの逆慣性,
}

impl 倍精度の接触の射影に参加する点 {
    /// 動的剛体の側。単精度の配置と質量特性と重心局所の点を倍精度へ広げ、腕と世界位置を倍精度で組み直す。
    pub(in crate::contact) fn 剛体の局所点から生成する(
        配置: &配置, 質量特性: &質量特性, 局所点: 変位<ローカル>
    ) -> Self {
        let 倍精度の配置 = 倍精度の剛体の配置::単精度の配置から広げる(配置);
        let 局所点 = 倍精度の三次元ベクトル::単精度の変位から広げる(局所点);
        Self {
            世界位置: 倍精度の配置.局所点の世界位置(&局所点),
            腕: 倍精度の配置.腕(&局所点),
            逆質量: f64::from(質量特性.逆質量().値()),
            ワールドの逆慣性: 倍精度のワールドの逆慣性::質量特性と配置から組む(質量特性, &倍精度の配置),
        }
    }

    /// 静的世界の接触相手の側。点そのものに動かせない参加者を置き、腕を零にする。
    pub(in crate::contact) fn 静的世界の固定点から生成する(世界位置: 位置<ワールド>) -> Self {
        Self {
            世界位置: 倍精度の三次元ベクトル::単精度の位置から広げる(世界位置),
            腕: 倍精度の三次元ベクトル::零(),
            逆質量: 0.0,
            ワールドの逆慣性: 倍精度のワールドの逆慣性::零(),
        }
    }

    pub(in crate::contact) fn 世界位置(&self) -> 倍精度の三次元ベクトル {
        self.世界位置
    }

    pub(in crate::contact) fn 動かせないか(&self) -> bool {
        self.逆質量 == 0.0
    }

    /// 同じ参加者に属する2つの点が、その参加者を通して結び付く一般化逆質量の交差の寄与
    /// w (n₁·n₂) + (r₁ × n₁)ᵀ I⁻¹ (r₂ × n₂)。
    /// 前提: 相手は自分と同じ参加者に属する点である(接触点集合の全部の点は同じ参加者の組を持つ)。
    pub(in crate::contact) fn 二つの点の一般化逆質量の交差の寄与(
        &self,
        自分の勾配の向き: &倍精度の三次元ベクトル,
        相手: &Self,
        相手の勾配の向き: &倍精度の三次元ベクトル,
    ) -> f64 {
        let 自分の外積 = self.腕.外積(自分の勾配の向き);
        let 相手の外積 = 相手.腕.外積(相手の勾配の向き);
        self.逆質量 * 自分の勾配の向き.内積(相手の勾配の向き) + 自分の外積.内積(&self.ワールドの逆慣性.ベクトルへ作用させる(&相手の外積))
    }

    /// 2つの点の世界位置の差を向きへ射影した量を解けたと見なす許容差 Σ_k |n_k| (ulp(p_k) + ulp(q_k)) ÷ 2。
    /// 単精度の側と同じ式であり、違うのは表現の刻みが倍精度のものであることだけである。
    pub(in crate::contact) fn 二つの点の世界位置の差を向きへ射影した解けたと見なす許容差(
        &self,
        相手: &Self,
        向き: &倍精度の三次元ベクトル,
    ) -> f64 {
        let (自分, 相手の位置) = (self.世界位置, 相手.世界位置);
        一成分の許容差(向き.x(), 自分.x(), 相手の位置.x())
            + 一成分の許容差(向き.y(), 自分.y(), 相手の位置.y())
            + 一成分の許容差(向き.z(), 自分.z(), 相手の位置.z())
    }
}

// 座標を倍精度へ収めるときの量子化の幅は、隣の表現できる値との差の半分である。単精度の側と同じ比である。
const 表現の刻みから座標の量子化への比: f64 = 0.5;

// 1つの座標軸の許容差。向きの成分の絶対値で2つの座標の量子化の幅を重み付けする。
// 3つの軸に対して対等な計算であるためレシーバを持たない。
fn 一成分の許容差(向きの成分: f64, 第1の座標: f64, 第2の座標: f64) -> f64 {
    (倍精度の表現の刻み幅(第1の座標) + 倍精度の表現の刻み幅(第2の座標)) * (向きの成分.abs() * 表現の刻みから座標の量子化への比)
}

// 倍精度の座標と隣の表現できる値との差。単精度の`メートル::表現の刻み幅`と同じ求め方である。
fn 倍精度の表現の刻み幅(座標: f64) -> f64 {
    let 絶対値 = 座標.abs();
    f64::from_bits(絶対値.to_bits() + 1) - 絶対値
}
