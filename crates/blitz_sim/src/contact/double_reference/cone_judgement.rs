//! 倍精度の参照計算が下すクーロン円錐の判定(Issue #59の数値契約の診断)。単精度の`manifold_cone`・
//! `manifold_tentative`・`tentative_point_multiplier`の3つが決める規則を、同じ場合分けで倍精度に写す。
//! 場合分けは3つである。法線の行が有効集合から外れた点は接線の乗数を零へ解放する。接線の行を積んだ点は
//! λ_t + Δs t を仮の値にする。行を積まなかった点(既に滑走中・接線変位が零・両方が動かせない)は前の反復の
//! 乗数を保つ。前の反復の接線の乗数は単精度の拘束の状態から広げて受け取る。参照計算は1つの反復の中だけを見る
//! ものであり、細分をまたいで積まれた乗数を自分で持たないためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::reference_solution::倍精度の参照の解;
use super::vector::倍精度の三次元ベクトル;

/// 倍精度の参照計算が求めた、接触点集合1つの円錐の判定の材料。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 倍精度の円錐の判定 {
    法線の乗数の合計: f64,
    接線の乗数の合力: 倍精度の三次元ベクトル,
    静止摩擦係数: f64,
}

impl 倍精度の円錐の判定 {
    /// 参照計算の解と、前の反復までの接線の乗数を持つ単精度の接触点集合から集計する。
    pub(in crate::contact) fn 参照の解と単精度の接触点集合から集計する(
        参照の解: &倍精度の参照の解,
        接触点集合: &[剛体と静的世界の接触拘束],
    ) -> Self {
        let 静止摩擦係数 = 接触点集合.first().map_or(0.0, |拘束| f64::from(拘束.引数().接触物性.静止摩擦係数().値()));
        let mut 接線の乗数の合力 = 倍精度の三次元ベクトル::零();
        for (点の番号, 拘束) in 接触点集合.iter().enumerate() {
            接線の乗数の合力 = 接線の乗数の合力.足す(&一点の仮の接線の乗数(参照の解, 拘束, 点の番号));
        }
        Self {
            法線の乗数の合計: 参照の解.更新後の法線の乗数の合計(),
            接線の乗数の合力,
            静止摩擦係数,
        }
    }

    pub(in crate::contact) fn 法線の乗数の合計(&self) -> f64 {
        self.法線の乗数の合計
    }

    /// 接線の乗数の合力の大きさ ‖Σλ_t‖。円錐の判定が読む量である。
    pub(in crate::contact) fn 接線の乗数の合力の大きさ(&self) -> f64 {
        self.接線の乗数の合力.長さ()
    }

    /// 合力と法線の乗数の合計の比 ‖Σλ_t‖ ÷ Σλ_n。静止摩擦係数と直に比べられる量である。
    pub(in crate::contact) fn 合力と法線の合計の比(&self) -> f64 {
        if self.法線の乗数の合計 > 0.0 {
            self.接線の乗数の合力の大きさ() / self.法線の乗数の合計
        } else {
            0.0
        }
    }

    /// 接線の乗数の合力がクーロン円錐の内側に留まっているか。偽なら接触点集合の全部の点が滑走へ移る。
    pub(in crate::contact) fn 円錐の内側か(&self) -> bool {
        self.接線の乗数の合力の大きさ() <= self.静止摩擦係数 * self.法線の乗数の合計
    }
}

// 接触点1つが円錐の判定へ渡す仮の接線の乗数。単精度の`接触点の仮の接線の乗数`と同じ場合分けである。
// 点1つの解と拘束の2つを対等に読む計算であり、どちらか一方を主語にできないためレシーバを持たない。
fn 一点の仮の接線の乗数(
    参照の解: &倍精度の参照の解,
    拘束: &剛体と静的世界の接触拘束,
    点の番号: usize,
) -> 倍精度の三次元ベクトル {
    if !参照の解.同時解.一点の法線の行が有効か(点の番号) {
        return 倍精度の三次元ベクトル::零();
    }
    let (x, y, z) = 拘束.静止摩擦の解の状態().接線のラグランジュ乗数().三つの成分();
    let 前の反復までの乗数 = 倍精度の三次元ベクトル::成分から生成する(f64::from(x.値()), f64::from(y.値()), f64::from(z.値()));
    match 参照の解.連立.接線の一行を読む(点の番号) {
        Some(接線の行) => 前の反復までの乗数.足す(&接線の行.接線の向き().比で伸ばす(参照の解.同時解.一点の接線の乗数の増分(点の番号))),
        None => 前の反復までの乗数,
    }
}
