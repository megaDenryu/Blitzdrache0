//! 倍精度の、接触点集合の法線の1行(Issue #59の数値契約の診断)。単精度の`非貫通の接触点集合の一行`が答える量
//! (隔たり・補正で閉じられる隔たり・連立の右辺・表現の刻み・乗数の上限)を同じ式で倍精度で答える。
//! 乗数の上限だけは単精度の行から広げて受け取る。この上限は1細分に詰めてよい貫通の長さという時間の側の予算で
//! あり、座標の表現の細かさで決まる量ではないためである。参照計算が独自の予算を持つと、相補条件の判定が
//! 単精度の側と別の理由で変わり、比べる意味が失われる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

#![cfg(test)]

use super::gradient::倍精度の一行の二つの符号付き勾配;
use super::participant_point::倍精度の接触の射影に参加する点;
use super::vector::倍精度の三次元ベクトル;

/// 倍精度の法線の1行。この細分で積んだ法線の乗数と、その乗数の上限と刻み依存量を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 倍精度の法線の一行 {
    勾配: 倍精度の一行の二つの符号付き勾配,
    法線のラグランジュ乗数: f64,
    乗数の上限: f64,
    刻み依存量: f64,
}

impl 倍精度の法線の一行 {
    pub(in crate::contact) fn 参加点と法線から生成する(
        第1の接触点: 倍精度の接触の射影に参加する点,
        第2の接触点: 倍精度の接触の射影に参加する点,
        接触法線: 倍精度の三次元ベクトル,
        法線のラグランジュ乗数: f64,
        乗数の上限: f64,
        刻み依存量: f64,
    ) -> Self {
        Self {
            勾配: 倍精度の一行の二つの符号付き勾配::法線の行として生成する(第1の接触点, 第2の接触点, 接触法線),
            法線のラグランジュ乗数,
            乗数の上限,
            刻み依存量,
        }
    }

    pub(in crate::contact) fn 勾配(&self) -> &倍精度の一行の二つの符号付き勾配 {
        &self.勾配
    }

    /// いまの配置での法線方向の隔たり d = (p_2 − p_1)·n。負が貫通である。
    pub(in crate::contact) fn 隔たり(&self) -> f64 {
        self.勾配.第2の勾配の向きへ射影した二つの点の世界位置の差()
    }

    /// この行の隔たりが持つ表現の刻み。有効集合の出し入れと相補条件の判定が読む。
    pub(in crate::contact) fn 隔たりの表現の刻み(&self) -> f64 {
        self.勾配.解けたと見なす許容差()
    }

    /// 補正で閉じられる隔たり。隔たりの大きさが表現の刻みを下回るときは零である。
    pub(in crate::contact) fn 補正で閉じられる隔たり(&self) -> f64 {
        let 刻み = self.隔たりの表現の刻み();
        if self.隔たり() < 刻み && self.隔たり() > -刻み {
            0.0
        } else {
            self.隔たり()
        }
    }

    /// この行の連立の右辺 −C − α̃ λ。
    pub(in crate::contact) fn 連立の右辺(&self) -> f64 {
        -self.補正で閉じられる隔たり() - self.法線のラグランジュ乗数 * self.刻み依存量
    }

    pub(in crate::contact) fn 法線のラグランジュ乗数(&self) -> f64 {
        self.法線のラグランジュ乗数
    }

    /// この細分でこの行が積んでよい乗数の上限。単精度の行から広げて受け取った値である。
    pub(in crate::contact) fn 乗数の上限(&self) -> f64 {
        self.乗数の上限
    }

    /// 連立の対角へ足すコンプライアンスの刻み依存量 α̃。
    pub(in crate::contact) fn 刻み依存量(&self) -> f64 {
        self.刻み依存量
    }

    pub(in crate::contact) fn 動かせない組か(&self) -> bool {
        self.勾配.動かせない組か()
    }
}
