//! 倍精度の、接触点集合1つの法線と接線を同じ対称行列へ入れた連立(Issue #59の数値契約の診断)。
//! 単精度の`接触点集合の法線と接線の連立`と同じ量(点ごとの2つの行と、抜き出しが読む口)を倍精度で持つ。
//! 解く工程は`subset_search`が、抜き出しは`reduced_system`が持つ。分けている理由は単精度の側と同じである。
//! 行を積むのが接触点集合の走査1回であるのに対し、解く工程は有効集合の部分集合ごとに抜き出しと求解を繰り返す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_collision::contact_set::接触点の上限;

use super::active_set::倍精度の連立の有効集合;
use super::gradient::倍精度の一行の二つの符号付き勾配;
use super::normal_row::倍精度の法線の一行;
use super::row_order::倍精度の抜き出した行の持ち主;
use super::tangential_row::倍精度の接線の一行;

/// 倍精度の、接触点集合1つの法線と接線の連立。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 倍精度の接触点集合の連立 {
    点ごとの法線の行: [Option<倍精度の法線の一行>; 接触点の上限],
    点ごとの接線の行: [Option<倍精度の接線の一行>; 接触点の上限],
    点の数: usize,
}

impl 倍精度の接触点集合の連立 {
    /// 1行も積んでいない連立。
    /// 注意: 点の数が接触点の上限を超える集合は衝突数学層の不変条件の破れであり、添字の範囲外として落ちる。
    pub(in crate::contact) fn 点の数から空で始める(点の数: usize) -> Self {
        Self {
            点ごとの法線の行: [None; 接触点の上限],
            点ごとの接線の行: [None; 接触点の上限],
            点の数,
        }
    }

    pub(in crate::contact) fn 法線の一行を積む(&mut self, 点の番号: usize, 一行: 倍精度の法線の一行) {
        self.点ごとの法線の行[点の番号] = Some(一行);
    }

    pub(in crate::contact) fn 接線の一行を積む(&mut self, 点の番号: usize, 一行: 倍精度の接線の一行) {
        self.点ごとの接線の行[点の番号] = Some(一行);
    }

    pub(in crate::contact) fn 点の数(&self) -> usize {
        self.点の数
    }

    pub(in crate::contact) fn 法線の一行を読む(&self, 点の番号: usize) -> Option<倍精度の法線の一行> {
        self.点ごとの法線の行[点の番号]
    }

    pub(in crate::contact) fn 接線の一行を読む(&self, 点の番号: usize) -> Option<倍精度の接線の一行> {
        self.点ごとの接線の行[点の番号]
    }

    /// 有効集合へ入れてよい点のビット並び。法線の行を持ち、どちらの参加者も動かせないのではない点である。
    pub(in crate::contact) fn 有効集合へ入れてよい点のビット並び(&self) -> u8 {
        let mut ビット並び = 0;
        for 点の番号 in 0..self.点の数 {
            if self.点ごとの法線の行[点の番号].is_some_and(|一行| !一行.動かせない組か()) {
                ビット並び |= 1u8 << 点の番号;
            }
        }
        ビット並び
    }

    /// 有効集合から外した点の法線の乗数を零へ解放する増分 −λ_n。法線の行を持たない点は零である。
    pub(in crate::contact) fn 外した点の法線の乗数を解放する増分(&self, 点の番号: usize) -> f64 {
        match self.点ごとの法線の行[点の番号] {
            Some(法線の行) => -法線の行.法線のラグランジュ乗数(),
            None => 0.0,
        }
    }

    /// 外した点の解放の増分が、渡した行の右辺の量を動かす長さ Σ_{j∉A} W_ij Δλ_j。
    pub(in crate::contact) fn 外した点の解放が動かす長さ(
        &self,
        行の勾配: &倍精度の一行の二つの符号付き勾配,
        有効集合: &倍精度の連立の有効集合,
    ) -> f64 {
        let mut 合計 = 0.0;
        for 点の番号 in (0..self.点の数).filter(|番号| !有効集合.有効か(*番号)) {
            if let Some(法線の行) = self.点ごとの法線の行[点の番号] {
                合計 += self.外した点の法線の乗数を解放する増分(点の番号) * 行の勾配.交差の寄与(法線の行.勾配());
            }
        }
        合計
    }

    pub(in crate::contact) fn 持ち主の行の勾配(
        &self,
        持ち主: 倍精度の抜き出した行の持ち主,
    ) -> Option<倍精度の一行の二つの符号付き勾配> {
        match 持ち主 {
            倍精度の抜き出した行の持ち主::法線の行を持つ点(番号) => self.点ごとの法線の行[番号].map(|一行| *一行.勾配()),
            倍精度の抜き出した行の持ち主::接線の行を持つ点(番号) => self.点ごとの接線の行[番号].map(|一行| *一行.勾配()),
        }
    }

    pub(in crate::contact) fn 持ち主の行の右辺(&self, 持ち主: 倍精度の抜き出した行の持ち主) -> f64 {
        match 持ち主 {
            倍精度の抜き出した行の持ち主::法線の行を持つ点(番号) => {
                self.点ごとの法線の行[番号].map_or(0.0, |一行| 一行.連立の右辺())
            }
            倍精度の抜き出した行の持ち主::接線の行を持つ点(番号) => {
                self.点ごとの接線の行[番号].map_or(0.0, |一行| 一行.連立の右辺())
            }
        }
    }

    /// 法線の行の対角へ足すコンプライアンスの刻み依存量 α̃。接線の行は硬い位置拘束であるため零である。
    pub(in crate::contact) fn 持ち主の行の対角へ足す刻み依存量(&self, 持ち主: 倍精度の抜き出した行の持ち主) -> f64 {
        match 持ち主 {
            倍精度の抜き出した行の持ち主::法線の行を持つ点(番号) => {
                self.点ごとの法線の行[番号].map_or(0.0, |一行| 一行.刻み依存量())
            }
            倍精度の抜き出した行の持ち主::接線の行を持つ点(_) => 0.0,
        }
    }
}
