//! 倍精度の、錨の接線変位を零へ戻す1行(Issue #59の数値契約の診断)。単精度の`錨の接線変位を零へ戻す一行`と
//! 同じ式を倍精度で書いたものであり、右辺は −(C_t − δ) である。δ の由来は倍精度の座標の表現の刻みである。
//! 2つの錨と接触法線から接線変位を求めて行を作る工程をこの型の生成が持つのは、接線変位が零の点を連立へ入れない
//! という判断をここで1度だけ下すためである。零の点は行を持たず、既存の接線の乗数を保つ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::gradient::倍精度の一行の二つの符号付き勾配;
use super::participant_point::倍精度の接触の射影に参加する点;
use super::vector::倍精度の三次元ベクトル;

/// 倍精度の接線の1行。この反復で拘束する接線の向きと、錨からの接線変位の長さを持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 倍精度の接線の一行 {
    勾配: 倍精度の一行の二つの符号付き勾配,
    接線の向き: 倍精度の三次元ベクトル,
    接線変位の長さ: f64,
}

impl 倍精度の接線の一行 {
    /// 2つの錨と接触法線からこの反復の1行を作る。接線変位が零の点は行を持たないため無しを返す。
    pub(in crate::contact) fn 二つの錨と接触法線から生成する(
        第1の錨: 倍精度の接触の射影に参加する点,
        第2の錨: 倍精度の接触の射影に参加する点,
        接触法線: &倍精度の三次元ベクトル,
    ) -> Option<Self> {
        if 第1の錨.動かせないか() && 第2の錨.動かせないか() {
            return None;
        }
        let 接線変位 = 第1の錨.世界位置().引く(&第2の錨.世界位置()).向きの成分を除く(接触法線);
        let 接線の向き = 接線変位.単位方向()?;
        Some(Self {
            勾配: 倍精度の一行の二つの符号付き勾配::接線の行として生成する(第1の錨, 第2の錨, 接線の向き),
            接線の向き,
            接線変位の長さ: 接線変位.長さ(),
        })
    }

    pub(in crate::contact) fn 勾配(&self) -> &倍精度の一行の二つの符号付き勾配 {
        &self.勾配
    }

    /// この反復でこの行が拘束する接線の向き t。進めた乗数はこの向きへ増分を足した値である。
    pub(in crate::contact) fn 接線の向き(&self) -> 倍精度の三次元ベクトル {
        self.接線の向き
    }

    /// 錨からの接線変位の長さ C_t。診断の表が単精度の側と比べる量である。
    pub(in crate::contact) fn 接線変位の長さ(&self) -> f64 {
        self.接線変位の長さ
    }

    /// 連立の右辺 −(C_t − δ)。閉じられる長さが正でなければ零である。
    pub(in crate::contact) fn 連立の右辺(&self) -> f64 {
        let 閉じられる長さ = self.接線変位の長さ - self.勾配.解けたと見なす許容差();
        if 閉じられる長さ > 0.0 { -閉じられる長さ } else { 0.0 }
    }
}
