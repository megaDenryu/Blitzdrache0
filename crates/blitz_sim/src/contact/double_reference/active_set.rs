//! 倍精度の参照計算の有効集合(Issue #59の数値契約の診断)。単精度の`法線と接線の連立の有効集合`と同じく、
//! 接触点の上限が8であるためビット並び1つで表す。取りうる集合が高々256個であることが表し方から読める。
//! 単精度の型をそのまま借りず写しを置くのは、あちらの生成が単精度の連立のモジュールに閉じており、参照計算が
//! 部分集合を自分で数え上げるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_collision::contact_set::接触点の上限;

/// 倍精度の参照計算が、いま法線の反力を持たせている接触点の集合。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub(in crate::contact) struct 倍精度の連立の有効集合 {
    ビット並び: u8,
}

impl 倍精度の連立の有効集合 {
    pub(in crate::contact) fn ビット並びから生成する(ビット並び: u8) -> Self {
        Self { ビット並び }
    }

    /// この接触点の法線の行がいま有効か。
    /// 注意: 接触点の上限以上の番号は衝突数学層の不変条件の破れであり、ここで落とす。
    pub(in crate::contact) fn 有効か(&self, 点の番号: usize) -> bool {
        assert!(点の番号 < 接触点の上限, "接触点の番号が接触点の上限を超えた: {点の番号}");
        self.ビット並び & (1u8 << 点の番号) != 0
    }

    pub(in crate::contact) fn ビット並び(&self) -> u8 {
        self.ビット並び
    }
}
