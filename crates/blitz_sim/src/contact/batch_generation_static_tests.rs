//! 剛体と静的世界の接触拘束の生成の試験(判断11)。担当するのは2つの性質を固定することである。静的世界の側の接触点が
//! 世界位置のまま持たれて接触点集合の点と一致すること、剛体の側だけが重心局所へ写されて世界へ戻ることである。
//! 剛体と剛体のバッチが空のままであることも同時に確かめ、参加者の組ごとにバッチが分かれていることを固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

#![allow(clippy::unwrap_used)]

use blitz_collision::shape::形の局所座標の位置;
use blitz_math::{ワールド, 位置};

use super::batch_builder::接触拘束のバッチの組み立て;
use super::contact_test_fixtures::{
    単一の材質の混合則, 台帳へ登録する, 接触に参加する剛体を作る, 試験の刻み幅, 静的世界の接触相手を作る
};
use super::stacked_box_fixture::{上の箱の配置, 上下の箱の接触点集合};
use crate::rigid_body::{剛体の台帳, 姿勢};
use crate::xpbd::コンプライアンス;

const 静的世界の番号: u32 = 7;

fn 世界の点が接触点と一致するか(戻した: 位置<ワールド>, 点: 形の局所座標の位置) -> bool {
    [
        f64::from(戻した.x().値()) - 点.xのメートル(),
        f64::from(戻した.y().値()) - 点.yのメートル(),
        f64::from(戻した.z().値()) - 点.zのメートル(),
    ]
    .iter()
    .all(|差| 差.abs() < 1.0e-6)
}

#[test]
fn 静的世界の側の接触点は世界位置のまま持たれ剛体の側だけが局所へ写る() {
    let 接触点集合 = 上下の箱の接触点集合(姿勢::恒等());
    let 上の配置 = 上の箱の配置(姿勢::恒等());
    let mut 台帳 = 剛体の台帳::空();
    let 剛体 = 接触に参加する剛体を作る(台帳へ登録する(&mut 台帳, 上の配置), 上の配置);
    let 相手 = 静的世界の接触相手を作る(静的世界の番号);
    let 混合則 = 単一の材質の混合則();
    let mut 組み立て = 接触拘束のバッチの組み立て::生成する(&混合則, コンプライアンス::硬い(), 試験の刻み幅(), 1);
    組み立て.剛体と静的世界の接触点集合を積む(&剛体, &相手, &接触点集合).unwrap();
    let バッチ = 組み立て.二つのバッチを組み立てる();
    assert!(バッチ.剛体どうしの接触拘束().is_empty());
    assert_eq!(バッチ.剛体と静的世界の接触拘束().len(), 接触点集合.件数());
    for (接触点, 拘束) in 接触点集合.接触点を順に並べる().zip(バッチ.剛体と静的世界の接触拘束()) {
        assert_eq!(拘束.引数().静的世界の接触相手.値(), 静的世界の番号);
        assert!(世界の点が接触点と一致するか(
            拘束.引数().静的世界側の接触点,
            接触点.第2の形の上の位置()
        ));
        assert!(世界の点が接触点と一致するか(
            上の配置.局所点の世界位置(拘束.引数().剛体側の局所接触点),
            接触点.第1の形の上の位置()
        ));
    }
}
