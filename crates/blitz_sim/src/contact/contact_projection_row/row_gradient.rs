//! 連立の1行が2つの参加者へ与える符号付きの勾配(判断12・判断13)。法線の行と接線の行を同じ対称行列へ入れるため、
//! 行がどちらの意味であっても `J_i M⁻¹ J_jᵀ` を同じ式で組めることをこの型が受け持つ。
//! 参加者ごとの符号を型が持つのは、法線と接線の交差の項の符号が「どちらの参加者から見た勾配か」で決まるためである。
//! 向きを1つだけ持って呼び出し側が道具を呼び分ける形にすると、法線どうしでは符号が打ち消し合って正しく見え、
//! 法線と接線の交差だけが符号を落とす。その誤りは行列の対称性でも検出できない。
//! 2つの参加点をこの型が所有するため、行の右辺が読む「2つの世界位置の差を向きへ射影した長さ」と、補正の長さを
//! 乗数へ換算する一般化逆質量の上界もこの型が答える。どちらも2つの参加点と向きだけで決まる量である。
//! 接触のモジュールの直下に置いているのは、非貫通だけの連立(`non_penetration`)と、法線と接線を同じ行列へ入れた
//! 連立(`normal_tangential_system`)の両方がこの型で行を組むためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::{メートル, ワールド, 方向, 符号付き逆キログラム, 逆キログラム};

use super::participant::接触の射影に参加する点;
use crate::rigid_xpbd::姿勢自由度の補正;
use crate::xpbd::ラグランジュ乗数;

/// 連立の1行が持つ、2つの参加者に対する符号付きの勾配。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 一行の二つの符号付き勾配 {
    第1の参加点: 接触の射影に参加する点,
    第1の勾配の向き: 方向<ワールド>,
    第2の参加点: 接触の射影に参加する点,
    第2の勾配の向き: 方向<ワールド>,
}

impl 一行の二つの符号付き勾配 {
    /// 法線の行の勾配。拘束は隔たり d = (p_2 − p_1)·n であり、勾配は第1へ −n、第2へ +n である。
    pub fn 法線の行として生成する(
        第1の接触点: 接触の射影に参加する点,
        第2の接触点: 接触の射影に参加する点,
        接触法線: 方向<ワールド>,
    ) -> Self {
        Self {
            第1の参加点: 第1の接触点,
            第1の勾配の向き: 接触法線.逆を向く方向(),
            第2の参加点: 第2の接触点,
            第2の勾配の向き: 接触法線,
        }
    }

    /// 接線の行の勾配。拘束は接線変位 Δ_t = a_1 − a_2 の長さであり、勾配は第1へ +t、第2へ −t である。
    pub fn 接線の行として生成する(
        第1の錨: 接触の射影に参加する点, 第2の錨: 接触の射影に参加する点, 接線の向き: 方向<ワールド>
    ) -> Self {
        Self {
            第1の参加点: 第1の錨,
            第1の勾配の向き: 接線の向き,
            第2の参加点: 第2の錨,
            第2の勾配の向き: 接線の向き.逆を向く方向(),
        }
    }

    /// この行と相手の行が2つの参加者を通して結び付く量 J_i M⁻¹ J_jᵀ。同じ行を2度渡せば対角の成分になる。
    pub fn 交差の寄与(&self, 相手: &Self) -> 符号付き逆キログラム {
        self.第1の参加点
            .二つの点の一般化逆質量の交差の寄与(self.第1の勾配の向き, &相手.第1の参加点, 相手.第1の勾配の向き)
            + self
                .第2の参加点
                .二つの点の一般化逆質量の交差の寄与(self.第2の勾配の向き, &相手.第2の参加点, 相手.第2の勾配の向き)
    }

    /// 乗数の増分を第1の参加者の補正へ分配する。呼び出し側は集合の全部の行の補正を合計してから1度だけ適用する。
    pub fn 乗数の増分を第1の参加者の補正へ分配する(&self, 乗数の増分: ラグランジュ乗数) -> 姿勢自由度の補正 {
        self.第1の参加点.乗数を補正へ分配する(self.第1の勾配の向き, 乗数の増分)
    }

    /// 乗数の増分を第2の参加者の補正へ分配する。静的世界の接触相手は動かせないため零の補正が返る。
    pub fn 乗数の増分を第2の参加者の補正へ分配する(&self, 乗数の増分: ラグランジュ乗数) -> 姿勢自由度の補正 {
        self.第2の参加点.乗数を補正へ分配する(self.第2の勾配の向き, 乗数の増分)
    }

    /// この行の右辺を解けたと見なす許容差 Σ_k |g_k| (ulp(p_1,k) + ulp(p_2,k)) ÷ 2。右辺は2つの世界位置の差を
    /// 勾配の向きへ射影した長さであるため、許容差は向きの成分ごとに座標の表現の刻みで決まる。
    /// 注意: 誤差の上限ではない。数えているのは座標の量子化だけである(`contact_projection_row`に理由がある)。
    pub fn 解けたと見なす許容差(&self) -> メートル {
        self.第1の参加点
            .二つの点の世界位置の差を向きへ射影した解けたと見なす許容差(&self.第2の参加点, self.第1の勾配の向き)
    }

    /// 2つの参加点の世界位置の差を第2の勾配の向きへ射影した長さ (p_2 − p_1)·g_2。法線の行ではこれが隔たりである。
    pub fn 第2の勾配の向きへ射影した二つの点の世界位置の差(&self) -> メートル {
        (self.第2の参加点.世界位置() - self.第1の参加点.世界位置()).方向に沿う長さ(self.第2の勾配の向き)
    }

    /// 2つの参加点の一般化逆質量の上界の和。補正を有限回転として適用したとき、乗数の増分1あたりに2つの参加点が
    /// 勾配の向きへ実際に離れる長さの上界である。長さと乗数の換算はこの値で行う。
    pub fn 一般化逆質量の上界の和(&self) -> 逆キログラム {
        self.第1の参加点.一般化逆質量の上界(self.第1の勾配の向き) + self.第2の参加点.一般化逆質量の上界(self.第2の勾配の向き)
    }

    /// どちらの参加者も動かせない行か。この行は連立から外す。
    pub fn 動かせない組か(&self) -> bool {
        self.第1の参加点.動かせないか() && self.第2の参加点.動かせないか()
    }
}
