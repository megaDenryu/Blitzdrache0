//! 衝突の問い合わせの基準原点に相対な座標から、行の解けたと見なす許容差 δ_i を導く工程(Issue #103の段階A2の候補(ζ)。
//! 試験と計器の専用)。勾配の定義(`row_gradient`)から分けているのは、あちらが本番の連立が読む量を答える型であり、
//! こちらが「δ_i を別の座標から導いたら何が変わるか」を測るためだけの計算だからである。本番はこの口を1度も呼ばない。
//!
//! 基準原点は、剛体力学層が接触点集合の問い合わせで選ぶ、第1の参加者の剛体の粗い位置である(判断3の2026-09-09の
//! 実装の細目)。この工程はその原点を粗い位置でなく第1の参加者の重心そのもので代表する。2つの差は粗い位置の刻みの
//! 半分以下であり、相対座標の表現の刻みを変えないためである。粗い位置を直に読む口はこのモジュールから呼べない
//! (`cargo xtask conform`が`基準原点を選ぶための粗い位置`の呼び出しを`contact/query_origin/`へ限る)。
//! 相対座標は、第1の参加点が腕そのもの、第2の参加点が「2つの点の世界位置の差 + 第1の参加点の腕」である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use blitz_math::{メートル, ワールド, 変位, 方向};

use super::一行の二つの符号付き勾配;

impl 一行の二つの符号付き勾配 {
    /// 基準原点に相対な座標の表現の刻みから導く δ_i = Σ_k |g_k| (ulp(r_1,k) + ulp(r_2,k)) ÷ 2(候補(ζ))。
    pub fn 基準原点に相対な座標から導く解けたと見なす許容差(&self) -> メートル {
        let 向き = self.第1の勾配の向き;
        let 第1の相対座標 = self.第1の参加点.腕();
        let 第2の相対座標 = (self.第2の参加点.世界位置() - self.第1の参加点.世界位置()) + 第1の相対座標;
        (向きへ射影した表現の刻み(第1の相対座標, 向き) + 向きへ射影した表現の刻み(第2の相対座標, 向き))
            * 表現の刻みから座標の量子化への比
    }
}

// 変位の各成分の表現の刻み幅を、向きの成分の絶対値で重み付けて足した長さ Σ_k |n_k| ulp(r_k)。
// 3つの成分に対して対等な計算であるためレシーバを持たない。
fn 向きへ射影した表現の刻み(相対座標: 変位<ワールド>, 向き: 方向<ワールド>) -> メートル {
    相対座標.x().表現の刻み幅() * 向き.x().abs() + 相対座標.y().表現の刻み幅() * 向き.y().abs() + 相対座標.z().表現の刻み幅() * 向き.z().abs()
}

