//! 非貫通が返す補正の試験(判断12・判断9)。担当するのは4つの性質を固定することである。重心から外れた接触点で姿勢の補正が
//! 生じること(重心の真上の接触点では生じないこと)、貫通量を生成時の値でなく現在の配置から求め直すこと、
//! 深い初期重なりで1細分の補正が形の最小の厚みへ切り詰められること、静的世界の側が補正を受けないことである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

