fn 局所点aを持つ拘束(局所接触点a: 変位<blitz_math::ローカル>) -> 剛体と剛体の接触拘束 {
    let 引数 = 剛体と剛体の接触拘束の引数 {
        局所接触点a,
        ..剛体どうしの基本の引数()
    };
    剛体と剛体の接触拘束::引数と刻み幅から生成する(引数, 試験の刻み幅()).unwrap()
}

fn 補正を取り出す(結果: 非貫通の一回の射影の結果) -> (姿勢自由度の補正, 姿勢自由度の補正) {
    let 非貫通の一回の射影の結果::補正した { 補正a, 補正b, .. } = 結果 else {
        panic!("貫通しているのに補正しなかった: {結果:?}");
    };
    (補正a, 補正b)
}

#[test]
fn 重心から外れた接触点でだけ姿勢が補正される() {
    let mut 重心の真下 = 局所点aを持つ拘束(変位::零());
    let (真下の補正a, _) = 補正を取り出す(重心の真下.一回射影する(&高さの参加者(-0.05), &高さの参加者(0.0)));
    assert_eq!(真下の補正a.回転().x().値(), 0.0);
    assert_eq!(真下の補正a.回転().z().値(), 0.0);
    let mut 外れた点 = 局所点aを持つ拘束(局所の変位を作る(0.5, 0.0, 0.0));
    let (外れた補正a, _) = 補正を取り出す(外れた点.一回射影する(&高さの参加者(-0.05), &高さの参加者(0.0)));
    assert!(外れた補正a.回転().z().値().abs() > 1.0e-4);
    assert!(外れた補正a.並進().y().値() > 0.0);
}

#[test]
fn 貫通量は生成時の値でなく現在の配置から求まる() {
    let 引数 = 剛体と剛体の接触拘束の引数 {
        生成時の貫通量: 貫通量::検査済みの長さから組む(メートル::生成する(0.05)),
        ..剛体どうしの基本の引数()
    };
    let mut 拘束 = 剛体と剛体の接触拘束::引数と刻み幅から生成する(引数, 試験の刻み幅()).unwrap();
    assert_eq!(拘束.引数().生成時の貫通量.長さ().値(), 0.05);
    let 結果 = 拘束.一回射影する(&高さの参加者(0.05), &高さの参加者(0.0));
    assert_eq!(結果, 非貫通の一回の射影の結果::離れている);
    assert_eq!(拘束.法線のラグランジュ乗数(), ラグランジュ乗数::零());
}

#[test]
fn 深い初期重なりの補正は形の最小の厚みへ切り詰められる() {
    let mut 拘束 = 局所点aを持つ拘束(変位::零());
    let (補正a, 補正b) = 補正を取り出す(拘束.一回射影する(&高さの参加者(-10.0), &高さの参加者(0.0)));
    let 詰めた長さ = 補正a.並進().y().値() - 補正b.並進().y().値();
    assert!((詰めた長さ - 試験の形の最小の厚み).abs() < 1.0e-5);
}

#[test]
fn 静的世界の側は補正を受けない() {
    let mut 拘束 = 剛体と静的世界の接触拘束::引数と刻み幅から生成する(剛体と静的世界の基本の引数(), 試験の刻み幅()).unwrap();
    let (補正a, 補正b) = 補正を取り出す(拘束.一回射影する(&高さの参加者(-0.05)));
    assert!(補正a.並進().y().値() > 0.0);
    assert_eq!(補正b, 姿勢自由度の補正::零());
    assert!(拘束.法線のラグランジュ乗数() > ラグランジュ乗数::零());
}
