//! 剛体と静的世界の接触拘束のうち、速度段階へ渡す値を組む操作(判断14)。細分の反復と速度の再構成を終えた後に1度だけ呼ばれる。
//! 錨に触れず、接触点と非貫通の乗数と滑走中の印だけを読む。速度段階が配置を書き換えないことは参加点の型が守る。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

use blitz_math::メートル毎秒;

use super::super::velocity_stage::速度段階の参加点;
use super::super::velocity_stage::速度段階の接触点の条件;
use super::剛体と静的世界の接触拘束;
use crate::rigid_body::運動状態;
use crate::rigid_xpbd::姿勢自由度の参加者;

impl 剛体と静的世界の接触拘束 {
    /// 速度段階の第1の参加点。細分の反復を終えた配置の参加者と、再構成した運動状態を渡す。
    pub fn 速度段階の剛体の参加点(&self, 剛体: &姿勢自由度の参加者, 運動状態: 運動状態) -> 速度段階の参加点 {
        速度段階の参加点::剛体から生成する(*剛体, self.引数.剛体側の局所接触点, 運動状態)
    }

    /// 速度段階の第2の参加点。静的世界の接触相手は速度を持たず、衝撃を受けても運動状態が変わらない。
    pub fn 速度段階の静的世界の参加点(&self) -> 速度段階の参加点 {
        速度段階の参加点::静的世界の固定点から生成する(self.引数.静的世界側の接触点)
    }

    /// 速度段階の条件。予測の前の法線相対速度は、細分の予測の時点で測った値を呼び出し側が渡す。
    pub fn 速度段階の条件を組む(&self, 予測の前の法線相対速度: メートル毎秒) -> 速度段階の接触点の条件 {
        速度段階の接触点の条件::生成する(
            self.引数.接触法線,
            self.引数.接触物性,
            self.非貫通の解の状態.法線のラグランジュ乗数(),
            予測の前の法線相対速度,
            self.静止摩擦の解の状態.滑走中か(),
        )
    }

    /// その細分で非貫通が実際に押し戻した接触点か。速度段階は偽の点を対象から外す(判断12の契約)。
    pub fn 最後の反復で押し戻したか(&self) -> bool {
        self.非貫通の解の状態.最後の反復で押し戻したか()
    }
}
