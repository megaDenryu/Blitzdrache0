/// 剛体と静的世界の接触拘束のバッチの1件。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 剛体と静的世界の接触拘束 {
    引数: 剛体と静的世界の接触拘束の引数,
    一刻みの係数: 非貫通の一刻みの係数,
    非貫通の解の状態: 非貫通の一細分の解の状態,
    錨: 剛体と静的世界の静止摩擦の錨,
    静止摩擦の解の状態: 静止摩擦の一細分の解の状態,
}

impl 剛体と静的世界の接触拘束 {
    /// 静的な引数と細分1本の刻み幅から作る。コンプライアンスの刻み依存量をここで1度だけ導く。
    /// 錨はこの細分の接触点に置いて始める。前の細分から続く接触は、履歴の併走が引き継いだ記録でこの後に置き直す。
    pub fn 引数と刻み幅から生成する(
        引数: 剛体と静的世界の接触拘束の引数,
        刻み幅: 刻み幅,
    ) -> Result<Self, コンプライアンスエラー> {
        Ok(Self {
            一刻みの係数: 引数.解き方.刻み幅で解く係数を導く(刻み幅)?,
            錨: 静止摩擦の錨::生成する(引数.剛体側の局所接触点, 引数.静的世界側の接触点),
            引数,
            非貫通の解の状態: 非貫通の一細分の解の状態::細分の開始の状態(),
            静止摩擦の解の状態: 静止摩擦の一細分の解の状態::細分の開始の状態(),
        })
    }

    /// 細分の間に変わらない値。接触の履歴の鍵・反復の順序・摩擦と速度段階がここから読む。
    pub fn 引数(&self) -> &剛体と静的世界の接触拘束の引数 {
        &self.引数
    }

    /// この細分で累積した法線方向のラグランジュ乗数。摩擦のクーロン円錐と速度段階がこれを読む。
    pub fn 法線のラグランジュ乗数(&self) -> ラグランジュ乗数 {
        self.非貫通の解の状態.法線のラグランジュ乗数()
    }

    /// この細分の静止摩擦の解の状態。滑走中の印を検査と計器が読む。
    pub fn 静止摩擦の解の状態(&self) -> 静止摩擦の一細分の解の状態 {
        self.静止摩擦の解の状態
    }

    // この細分でいま置かれている錨。錨からの接線変位を測る計器が読む口であり、公開面には出さない。
    #[cfg(test)]
    pub(in crate::contact) fn 静止摩擦の錨(&self) -> 剛体と静的世界の静止摩擦の錨 {
        self.錨
    }

    /// 接触点集合の法線を同時に解く連立へ渡す1行。剛体の側の参加点はこの反復の予測の配置から作る。
    pub fn 同時解法の一行にする(&self, 剛体: &姿勢自由度の参加者) -> 非貫通の接触点集合の一行 {
        非貫通の接触点集合の一行::生成する(
            接触の射影に参加する点::剛体の局所点から生成する(*剛体, self.引数.剛体側の局所接触点),
            接触の射影に参加する点::静的世界の固定点から生成する(self.引数.静的世界側の接触点),
            self.引数.接触法線,
            self.非貫通の解の状態,
            self.一刻みの係数,
        )
    }

    /// 同時解法が求めた乗数の増分を取り込む。前提: 一行はこの拘束から作ったものである。
    pub fn 同時解法の乗数の増分を取り込む(
        &mut self, 一行: &非貫通の接触点集合の一行, 乗数の増分: ラグランジュ乗数
    ) {
        self.非貫通の解の状態 = 一行.乗数の増分を足した解の状態(乗数の増分);
    }

    /// 法線と接線の連立へこの点の法線の一行を積む。この行が求めるのは、接線の補正がこの隔たりを動かさないことである。
    pub fn 法線と接線の連立へ法線の一行を積む(
        &self,
        点の番号: usize,
        連立: &mut 接触点集合の法線と接線の連立,
        剛体: &姿勢自由度の参加者,
    ) {
        連立.法線の一行を積む(
            点の番号,
            法線の隔たりを動かさない一行::接触点と法線の乗数から生成する(
                接触の射影に参加する点::剛体の局所点から生成する(*剛体, self.引数.剛体側の局所接触点),
                接触の射影に参加する点::静的世界の固定点から生成する(self.引数.静的世界側の接触点),
                self.引数.接触法線,
                self.法線のラグランジュ乗数(),
            ),
        );
    }

    /// 法線と接線の連立が求めた法線の乗数の増分を取り込む。前提: 剛体はその連立を組んだときの参加者である。
    /// 1細分に詰めてよい長さの累計は判断12と同じ換算で進める(負の増分では戻さない)。
    pub fn 法線と接線の連立の法線の乗数の増分を取り込む(
        &mut self, 剛体: &姿勢自由度の参加者, 乗数の増分: ラグランジュ乗数
    ) {
        self.非貫通の解の状態 = self.同時解法の一行にする(剛体).乗数の増分を足した解の状態(乗数の増分);
    }

    /// 非貫通を一回射影し、乗数を更新する。呼び出し側は返った剛体の側の補正を予測の状態へ適用する。
    pub fn 一回射影する(&mut self, 剛体: &姿勢自由度の参加者) -> 非貫通の一回の射影の結果 {
        let 結果 = self.一刻みの係数.一回射影する(
            接触の射影に参加する点::剛体の局所点から生成する(*剛体, self.引数.剛体側の局所接触点),
            接触の射影に参加する点::静的世界の固定点から生成する(self.引数.静的世界側の接触点),
            self.引数.接触法線,
            self.非貫通の解の状態,
        );
        if let 非貫通の一回の射影の結果::補正した {
            更新後の解の状態, ..
        } = 結果
        {
            self.非貫通の解の状態 = 更新後の解の状態;
        }
        結果
    }
}
