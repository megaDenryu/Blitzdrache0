//! 剛体と静的世界の接触点1つの拘束(判断11)。剛体と剛体の接触拘束と同じ射影の式を読み、違うのは第2の参加者の
//! 点の取り方だけである(静的世界の接触相手は動かせない参加者を接触点そのものに置く)。
//! 細分の開始で生成し細分の終了で捨てる一時の値であり、乗数は細分の開始で0から始める(判断16の暖機はしない)。
//! 錨と静止摩擦の解の状態は細分を跨いで引き継ぐ値と、細分の中だけの値に分かれる。前者は判断16の履歴が保ち、
//! この型はその細分のあいだ借りて持つ。この型を子モジュールへ分けているのは、錨と静止摩擦の解の状態を
//! 接触のモジュール全体へ書き換え可能な形で見せないためである(Rustの可視性はモジュール木で決まる)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

