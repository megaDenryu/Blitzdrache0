//! 持ち越す接線の残差の消費と破棄の試験(判断24の反証(d))。担当するのは5つの性質を固定することである。
//! 継続で持ち込んだ値と細分の終わりに測った値の差が残差の変化になること、履歴へ書き戻す値が測り直した値そのもの
//! であって持ち込んだ値との和でないこと、接触が始まった細分は持ち込みが無く変化も無いこと、錨を置き直した細分と
//! 接線の乗数を零へ解放した細分で持ち込みが破棄されること、法線反力が無い点が残差を持たないことである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 変位, 方向};

use super::super::contact_test_fixtures::{世界の位置を作る, 動的な参加者を作る, 試験の刻み幅};
use super::super::history::接触の継続の記録;
use super::super::non_penetration::fixture::{剛体と静的世界の基本の引数, 高さの参加者, 高さの配置};
use super::super::static_friction::持ち越す接線の残差;
use super::剛体と静的世界の接触拘束;
use crate::rigid_body::姿勢;
use crate::rigid_xpbd::姿勢自由度の参加者;

const 持ち込む長さ: f32 = 1.0e-6;
const 測り直す長さ: f32 = 3.0e-6;

fn x軸の変位(長さ: f32) -> 変位<ワールド> {
    変位::方向へ進む(方向::生成する(1.0, 0.0, 0.0).unwrap(), メートル::生成する(長さ))
}

// 錨からx軸の向きへ指定の長さだけずれた配置の参加者。錨は原点にあり、接触法線は下向きである。
fn 滑らせた参加者(滑らせる長さ: f32) -> 姿勢自由度の参加者 {
    動的な参加者を作る(
        crate::rigid_body::配置::生成する(世界の位置を作る(滑らせる長さ, 0.0, 0.0), 姿勢::恒等()),
        1.0,
        1.0,
    )
}

// 法線反力を積んだ拘束。残差を持つのは法線反力が在る点だけであるため、測る前にこれを通す。
fn 押し戻した拘束() -> 剛体と静的世界の接触拘束 {
    let mut 拘束 = 剛体と静的世界の接触拘束::引数と刻み幅から生成する(剛体と静的世界の基本の引数(), 試験の刻み幅()).unwrap();
    let _ = 拘束.一回射影する(&高さの参加者(-0.05));
    拘束
}

// 前の細分から残差を持ち込んだ拘束。錨と接触法線はこの拘束のものをそのまま引き継ぐ。
fn 残差を持ち込んだ拘束() -> 剛体と静的世界の接触拘束 {
    let mut 拘束 = 押し戻した拘束();
    let 記録 = 接触の継続の記録::生成する(
        拘束.静止摩擦の錨(),
        拘束.引数().接触法線,
        持ち越す接線の残差::測った変位から生成する(x軸の変位(持ち込む長さ)),
    );
    拘束.継続の記録を引き継ぐ(記録);
    拘束
}

#[test]
fn 持ち込んだ残差と測り直した残差の差が残差の変化になる() {
    let mut 拘束 = 残差を持ち込んだ拘束();
    拘束.細分の終わりの接線の残差を測る(&滑らせた参加者(測り直す長さ));
    let 変化 = 拘束.接線の残差の持ち越し.細分のあいだの残差の変化().unwrap();
    assert!((変化.x().値() - (測り直す長さ - 持ち込む長さ)).abs() < 1.0e-12);
}

#[test]
fn 履歴へ書き戻す残差は測り直した値であり持ち込んだ値との和ではない() {
    let mut 拘束 = 残差を持ち込んだ拘束();
    拘束.細分の終わりの接線の残差を測る(&滑らせた参加者(測り直す長さ));
    let 書き戻す = 拘束.接線の残差の持ち越し.履歴へ書き戻す残差().測った変位().unwrap();
    assert!((書き戻す.x().値() - 測り直す長さ).abs() < 1.0e-12);
}

#[test]
fn 接触が始まった細分は持ち込みが無く残差の変化も無い() {
    let mut 拘束 = 残差を持ち込んだ拘束();
    拘束.開始した接触の錨を予測の前の配置へ置く(&高さの配置(0.0));
    拘束.細分の終わりの接線の残差を測る(&滑らせた参加者(測り直す長さ));
    assert!(拘束.接線の残差の持ち越し.細分のあいだの残差の変化().is_none());
}

#[test]
fn 錨を置き直した細分は持ち込みを破棄する() {
    let mut 拘束 = 残差を持ち込んだ拘束();
    拘束.接触点集合が滑走中になったと印す(&高さの参加者(0.0));
    拘束.細分の終わりの接線の残差を測る(&滑らせた参加者(測り直す長さ));
    assert!(拘束.接線の残差の持ち越し.細分のあいだの残差の変化().is_none());
}

#[test]
fn 接線の乗数を零へ解放した細分は持ち込みを破棄する() {
    let mut 拘束 = 残差を持ち込んだ拘束();
    拘束.静止摩擦の接線の乗数を零へ解放する();
    拘束.細分の終わりの接線の残差を測る(&滑らせた参加者(測り直す長さ));
    assert!(拘束.接線の残差の持ち越し.細分のあいだの残差の変化().is_none());
}

#[test]
fn 法線反力が無い点は細分の終わりの残差を持たない() {
    let mut 拘束 = 剛体と静的世界の接触拘束::引数と刻み幅から生成する(剛体と静的世界の基本の引数(), 試験の刻み幅()).unwrap();
    拘束.細分の終わりの接線の残差を測る(&滑らせた参加者(測り直す長さ));
    assert_eq!(拘束.接線の残差の持ち越し.履歴へ書き戻す残差(), 持ち越す接線の残差::無し);
}
