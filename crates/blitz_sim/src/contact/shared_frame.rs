//! 接触点集合が返す共有の座標系の値を、剛体の解法が使うワールドの単精度の型へ写す境界(判断11)。
//! 接触点集合は2つの形が共有する1つの局所座標系で点と法線を返す。初版はこの共有の座標系をワールドとするため、
//! ここが行うのは座標系の名前の付け替えと、倍精度から単精度への縮小の2つだけである。
//! 縮小をこの1箇所へ閉じるのは、剛体の状態と接触の精度が単精度であり(未決定の事項5)、狭める場所が増えると
//! 同じ点が経路ごとに違う値になるためである。共有の座標系をワールド以外に取る日は、ここが座標変換を持つ。
//! 3つの関数が自由関数であるのは、入力が `blitz_collision` の型でありこちらの型のメソッドにできないためである。
//! どれも依存も副作用も持たない純粋な変換である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use blitz_collision::contact_set::貫通量メートル;
use blitz_collision::shape::形の局所座標の位置;
use blitz_math::{メートル, ローカル, ワールド, 位置, 倍精度の無次元量を単精度へ狭める, 方向};

use super::generation_error::接触拘束の生成エラー;
use super::penetration_depth::貫通量;

pub(super) fn 接触点の位置をワールドへ写す(
    点: 形の局所座標の位置
) -> Result<位置<ワールド>, 接触拘束の生成エラー> {
    Ok(位置::生成する(
        メートルへ狭める(点.xのメートル())?,
        メートルへ狭める(点.yのメートル())?,
        メートルへ狭める(点.zのメートル())?,
    ))
}

pub(super) fn 接触法線をワールドへ写す(法線: 方向<ローカル>) -> Result<方向<ワールド>, 接触拘束の生成エラー> {
    Ok(方向::生成する(法線.x(), 法線.y(), 法線.z())?)
}

pub(super) fn 貫通量を単精度へ狭める(貫通: 貫通量メートル) -> Result<貫通量, 接触拘束の生成エラー> {
    let 長さ = 倍精度の無次元量を単精度へ狭める(貫通.値()).map_err(接触拘束の生成エラー::貫通量を狭められない)?;
    Ok(貫通量::検査済みの長さから組む(メートル::生成する(長さ)))
}

fn メートルへ狭める(値: f64) -> Result<メートル, 接触拘束の生成エラー> {
    let 狭めた = 倍精度の無次元量を単精度へ狭める(値).map_err(接触拘束の生成エラー::接触点の位置を狭められない)?;
    Ok(メートル::生成する(狭めた))
}
