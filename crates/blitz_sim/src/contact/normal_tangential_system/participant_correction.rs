//! 解いた同時解が2つの参加者へ与える補正の合計を組む工程(判断9・判断12・判断13)。
//! 有効集合を探す工程(`subset_search`)から分けているのは、あちらが「どの部分集合を解くか」を決める局面であり、
//! こちらが「決まった解を参加者ごとの1つの補正へ配る」局面だからである。触れるのは点ごとの2つの行の勾配と、
//! 渡された同時解の増分だけであり、部分集合も相補条件も読まない。
//! 点ごとに配置へ適用せず合計を返すのは、1点ずつ適用すると次の点の腕と有効逆質量が変わり、同じ連立を解いた
//! 意味が壊れるためである。呼び出し側はこの合計を1度だけ適用する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断9: 拘束の勾配から並進と回転の補正を一般化逆質量で分配し、確定後に速度と角速度を再構成する」

use super::solution::接触点集合の法線と接線の同時解;
use super::system::接触点集合の法線と接線の連立;
use crate::contact::contact_projection_row::一行の二つの符号付き勾配;
use crate::rigid_xpbd::姿勢自由度の補正;
use crate::xpbd::ラグランジュ乗数;

// 補正を受け取る側の参加者。1行の勾配は2つの参加者へ符号違いで分配されるため、どちらへ配るかをこの列挙が表す。
#[derive(Clone, Copy)]
enum 補正を受け取る参加者 {
    第1の参加者,
    第2の参加者,
}

impl 補正を受け取る参加者 {
    fn 一行の勾配から補正を分配する(
        self, 勾配: &一行の二つの符号付き勾配, 増分: ラグランジュ乗数
    ) -> 姿勢自由度の補正 {
        match self {
            Self::第1の参加者 => 勾配.乗数の増分を第1の参加者の補正へ分配する(増分),
            Self::第2の参加者 => 勾配.乗数の増分を第2の参加者の補正へ分配する(増分),
        }
    }
}

impl 接触点集合の法線と接線の連立 {
    /// 求めた増分が剛体(第1の参加者)へ与える補正の合計。
    pub fn 第1の参加者への補正の合計(&self, 同時解: &接触点集合の法線と接線の同時解) -> 姿勢自由度の補正 {
        self.二つの行の増分を配って合計する(同時解, 補正を受け取る参加者::第1の参加者)
    }

    /// 求めた増分が第2の参加者へ与える補正の合計。静的世界の接触相手は動かせないため零の補正が返る。
    pub fn 第2の参加者への補正の合計(&self, 同時解: &接触点集合の法線と接線の同時解) -> 姿勢自由度の補正 {
        self.二つの行の増分を配って合計する(同時解, 補正を受け取る参加者::第2の参加者)
    }

    // 点ごとの法線の行と接線の行の増分を、指定した参加者の補正へ写して足し合わせる。
    fn 二つの行の増分を配って合計する(
        &self,
        同時解: &接触点集合の法線と接線の同時解,
        受け取る参加者: 補正を受け取る参加者,
    ) -> 姿勢自由度の補正 {
        let mut 合計 = 姿勢自由度の補正::零();
        for 点の番号 in 0..self.点の数() {
            if let Some(法線の行) = self.法線の一行を読む(点の番号) {
                let 増分 = 同時解.一点の法線の乗数の増分(点の番号);
                合計 = 合計.合わせる(&受け取る参加者.一行の勾配から補正を分配する(法線の行.勾配(), 増分));
            }
            if let Some(接線の行) = self.接線の一行を読む(点の番号) {
                let 増分 = 同時解.一点の接線の乗数の増分(点の番号);
                合計 = 合計.合わせる(&受け取る参加者.一行の勾配から補正を分配する(接線の行.勾配(), 増分));
            }
        }
        合計
    }
}
