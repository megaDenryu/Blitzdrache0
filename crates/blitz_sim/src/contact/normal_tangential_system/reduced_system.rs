//! 有効集合に絞った法線と接線の連立(判断12・判断13)。並びが決めた行の勾配から対称行列 J M⁻¹ Jᵀ を組み、
//! 法線の行の対角へコンプライアンスの刻み依存量 α̃ を足し、行ごとの右辺と、その右辺を解けたと見なす許容差を
//! 添えて擬似逆で解く。有効集合から外れた点の法線の乗数は零へ解放するため、その解放が有効な行の隔たりを動かす
//! 長さを右辺から引く。
//! 並びの型から分けているのは、こちらが数値を持ち、あちらが番号の対応だけを持つからである。
//! 解いた行の残差と補正の大きさを測る工程は`reduced_system_residual`が持つ。
//! 正則化を足さず擬似逆で解くのは、この材料が剛体1つの運動では実現できない右辺の成分を含むためである
//! (理由の全文は `crates/blitz_sim/src/contact/symmetric_system/pseudo_inverse.rs` にある)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::super::contact_projection_row::一行の二つの符号付き勾配;
use super::super::symmetric_system::{
    対称な連立の固有分解, 擬似逆で解いた増分と捨てた右辺, 法線と接線の連立の行の上限
};
use super::active_set::法線と接線の連立の有効集合;
use super::row_order::抜き出した行の並び;
use super::system::接触点集合の法線と接線の連立;
#[cfg(test)]
use super::tolerance_candidate::擬似逆が右辺の向きを捨てる判定の当て方;

/// 有効集合の行だけを抜き出した対称な連立。
pub(super) struct 有効な行だけを抜き出した連立 {
    pub(super) 並び: 抜き出した行の並び,
    pub(super) 対称行列: [[f32; 法線と接線の連立の行の上限]; 法線と接線の連立の行の上限], // 毎キログラム
    pub(super) 定数項: [f32; 法線と接線の連立の行の上限],                                 // メートル
    pub(super) 行ごとの解けたと見なす許容差: [f32; 法線と接線の連立の行の上限],           // メートル
    #[cfg(test)]
    pub(super) 右辺の向きを捨てる判定: 擬似逆が右辺の向きを捨てる判定の当て方, // 候補(α)の軸。本番の構成はこの欄を持たない
}

// 候補(α)が擬似逆へ渡す許容差。全部の行で零であるため、|β_k| ≤ δ_k の判定は偽の固有値でない向きを1つも捨てない。
#[cfg(test)]
const 零の行ごとの許容差: [f32; 法線と接線の連立の行の上限] = [0.0; 法線と接線の連立の行の上限];

impl 有効な行だけを抜き出した連立 {
    pub(super) fn 抜き出す(連立: &接触点集合の法線と接線の連立, 有効集合: &法線と接線の連立の有効集合) -> Self {
        let 並び = 抜き出した行の並び::有効集合から組む(連立, 有効集合);
        let mut 抜き出した = Self {
            対称行列: [[0.0; 法線と接線の連立の行の上限]; 法線と接線の連立の行の上限],
            定数項: [0.0; 法線と接線の連立の行の上限],
            行ごとの解けたと見なす許容差: [0.0; 法線と接線の連立の行の上限],
            #[cfg(test)]
            右辺の向きを捨てる判定: 擬似逆が右辺の向きを捨てる判定の当て方::行ごとの許容差で捨てる,
            並び,
        };
        let 行ごとの勾配 = 抜き出した.行ごとの勾配を読む(連立);
        for (k, 自分) in 行ごとの勾配.iter().enumerate().take(抜き出した.並び.行の数()) {
            let Some(自分) = 自分 else { continue };
            抜き出した.一行の数値を埋める(連立, 有効集合, &行ごとの勾配, k, 自分);
        }
        #[cfg(test)]
        抜き出した.試験の許容差の当て方を反映する(連立, 有効集合);
        抜き出した
    }

    /// 擬似逆で解いた行ごとの増分と、許容差の内側として捨てた右辺。点の番号へ戻すのは`もとの点へ戻す`である。
    pub(super) fn 解く(&self) -> 擬似逆で解いた増分と捨てた右辺 {
        対称な連立の固有分解::分解する(&self.対称行列, self.並び.行の数()).擬似逆で解く(&self.定数項, self.擬似逆が比べる行ごとの許容差())
    }

    /// 擬似逆が右辺の固有の向きを捨てるときに比べる行ごとの許容差。本番は組み立てた許容差そのものである。
    #[cfg(not(test))]
    pub(super) fn 擬似逆が比べる行ごとの許容差(&self) -> &[f32; 法線と接線の連立の行の上限] {
        &self.行ごとの解けたと見なす許容差
    }

    /// 同じ口の試験の構成。候補(α)の当て方だけが零の許容差を返し、右辺の向きを捨てる判定を無効にする。
    #[cfg(test)]
    pub(super) fn 擬似逆が比べる行ごとの許容差(&self) -> &[f32; 法線と接線の連立の行の上限] {
        match self.右辺の向きを捨てる判定 {
            擬似逆が右辺の向きを捨てる判定の当て方::行ごとの許容差で捨てる => &self.行ごとの解けたと見なす許容差,
            擬似逆が右辺の向きを捨てる判定の当て方::捨てずに真の向きを全部解く => &零の行ごとの許容差,
        }
    }

    // 抜き出した並びの順に読んだ行の勾配。行列の組み立てが行どうしの交差を取るため、先に一覧にする。
    fn 行ごとの勾配を読む(
        &self,
        連立: &接触点集合の法線と接線の連立,
    ) -> [Option<一行の二つの符号付き勾配>; 法線と接線の連立の行の上限] {
        let mut 勾配 = [None; 法線と接線の連立の行の上限];
        for (k, 一つ) in 勾配.iter_mut().enumerate().take(self.並び.行の数()) {
            *一つ = 連立.持ち主の行の勾配(self.並び.第k行の持ち主(k));
        }
        勾配
    }

    // 第k行の対称行列・定数項・許容差を埋める。定数項からは、外した点の解放がこの行を動かす長さを引く。
    fn 一行の数値を埋める(
        &mut self,
        連立: &接触点集合の法線と接線の連立,
        有効集合: &法線と接線の連立の有効集合,
        行ごとの勾配: &[Option<一行の二つの符号付き勾配>; 法線と接線の連立の行の上限],
        k: usize,
        自分: &一行の二つの符号付き勾配,
    ) {
        for (l, 相手) in 行ごとの勾配.iter().enumerate().take(self.並び.行の数()) {
            if let Some(相手) = 相手 {
                self.対称行列[k][l] = 自分.交差の寄与(相手).値();
            }
        }
        let 持ち主 = self.並び.第k行の持ち主(k);
        self.対称行列[k][k] += 連立.持ち主の行の対角へ足す刻み依存量(持ち主);
        self.定数項[k] = (連立.持ち主の行の右辺(持ち主) - 連立.外した点の解放が動かす長さ(自分, 有効集合)).値();
        self.行ごとの解けたと見なす許容差[k] = 自分.解けたと見なす許容差().値();
    }
}
