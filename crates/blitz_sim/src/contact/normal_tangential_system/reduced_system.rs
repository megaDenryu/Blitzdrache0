//! 有効集合に絞った法線と接線の連立(判断12・判断13)。並びが決めた行の勾配から対称行列 J M⁻¹ Jᵀ を組み、
//! 法線の行の対角へコンプライアンスの刻み依存量 α̃ を足し、行ごとの右辺と、その右辺を解けたと見なす許容差を
//! 添えて擬似逆で解く。有効集合から外れた点の法線の乗数は零へ解放するため、その解放が有効な行の隔たりを動かす
//! 長さを右辺から引く。
//! 並びの型から分けているのは、こちらが数値を持ち、あちらが番号の対応だけを持つからである。
//! 解いた行の残差と補正の大きさを測る工程は`reduced_system_residual`が持つ。
//! 正則化を足さず擬似逆で解くのは、この材料が剛体1つの運動では実現できない右辺の成分を含むためである
//! (理由の全文は `crates/blitz_sim/src/contact/symmetric_system/pseudo_inverse.rs` にある)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

