//! 固有の向き1つだけを解いた乗数の増分が、剛体(第1の参加者)の一般化自由度へ入れる補正を読む工程
//! (Issue #103の段階B。試験と計器の専用)。
//! 解を点へ戻す工程(`reduced_system_point_mapping`)から分けているのは、あちらが本番の解を配る工程であり、
//! 有効集合から外した点の乗数を零へ解放する増分をそこで足すからである。こちらが読みたいのは Jᵀ Δλ そのもの
//! だけであり、解放の増分を足すと、向き1つの補正へその向きと関わらない量が混ざる。
//! 並進と回転を分けて持つのは、その向きを解いた結果が箱を滑らせるのか回すのかを呼び出し側が分けるためである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use blitz_collision::contact_set::接触点の上限;
use blitz_math::{メートル, ラジアン};

use super::super::symmetric_system::{対称な連立の固有分解, 法線と接線の連立の行の上限};
use super::active_set::法線と接線の連立の有効集合;
use super::reduced_system::有効な行だけを抜き出した連立;
use super::solution::接触点集合の法線と接線の同時解;
use super::system::接触点集合の法線と接線の連立;
use crate::xpbd::ラグランジュ乗数;

/// 乗数の増分 Δλ が剛体の一般化自由度へ入れる補正の大きさ。並進と回転を別々の単位で持つ。
pub(in crate::contact) struct 剛体の一般化自由度へ入る補正の大きさ {
    pub(in crate::contact) 並進の長さ: メートル,
    pub(in crate::contact) 回転の大きさ: ラジアン,
}

impl 剛体の一般化自由度へ入る補正の大きさ {
    /// 表へ綴る形。
    pub(in crate::contact) fn 綴り(&self) -> String {
        format!("並進={:.4e} 回転={:.4e}", self.並進の長さ.値(), self.回転の大きさ.値())
    }
}

impl 有効な行だけを抜き出した連立 {
    /// 第k番の固有の向きだけを解いた増分 (β_k ÷ λ_k) v_k が、剛体へ入れる補正の大きさ。
    pub(in crate::contact) fn 第k番の向きが剛体へ入れる補正(
        &self,
        連立: &接触点集合の法線と接線の連立,
        有効集合: &法線と接線の連立の有効集合,
        分解: &対称な連立の固有分解,
        k: usize,
    ) -> 剛体の一般化自由度へ入る補正の大きさ {
        let 同時解 = self.第k番の向きだけの増分を点へ写す(連立, 有効集合, 分解, k);
        let 補正 = 連立.第1の参加者への補正の合計(&同時解);
        剛体の一般化自由度へ入る補正の大きさ {
            並進の長さ: 補正.並進().長さ(),
            回転の大きさ: 補正.回転().長さ(),
        }
    }

    // 第k番の向きだけを解いた行ごとの増分を、点ごとの増分へ写す。外した点の乗数の解放は足さない。
    fn 第k番の向きだけの増分を点へ写す(
        &self,
        連立: &接触点集合の法線と接線の連立,
        有効集合: &法線と接線の連立の有効集合,
        分解: &対称な連立の固有分解,
        k: usize,
    ) -> 接触点集合の法線と接線の同時解 {
        let 増分 = self.第k番の向きだけの行ごとの増分(分解, k);
        let mut 法線の増分 = [ラグランジュ乗数::零(); 接触点の上限];
        let mut 接線の増分 = [ラグランジュ乗数::零(); 接触点の上限];
        for 行 in 0..self.並び.法線の行の数() {
            法線の増分[self.並び.法線の行のもとの点の番号(行)] =
                ラグランジュ乗数::有効逆質量で割った長さから生成する(増分[行]);
        }
        for 行 in 0..self.並び.接線の行の数() {
            接線の増分[self.並び.接線の行のもとの点の番号(行)] =
                ラグランジュ乗数::有効逆質量で割った長さから生成する(増分[self.並び.法線の行の数() + 行]);
        }
        let mut 同時解 = 接触点集合の法線と接線の同時解::空();
        for 点の番号 in 0..連立.点の数() {
            同時解.一点の解を書き込む(点の番号, 法線の増分[点の番号], 接線の増分[点の番号], 有効集合.有効か(点の番号));
        }
        同時解
    }

    // 第k番の向きだけを解いた行ごとの増分 (β_k ÷ λ_k) v_k。他の向きは1つも足さない。
    fn 第k番の向きだけの行ごとの増分(
        &self, 分解: &対称な連立の固有分解, k: usize
    ) -> [f32; 法線と接線の連立の行の上限] {
        let 固有値 = 分解.第k番の固有値(k);
        let mut 増分 = [0.0; 法線と接線の連立の行の上限];
        if 固有値 <= 0.0 {
            return 増分;
        }
        let 係数 = 分解.第k番の向きへの射影(k, &self.定数項) / 固有値;
        for (行, 値) in 増分.iter_mut().enumerate().take(self.並び.行の数()) {
            *値 = 係数 * 分解.第k番の固有ベクトルの成分(k, 行);
        }
        増分
    }
}
