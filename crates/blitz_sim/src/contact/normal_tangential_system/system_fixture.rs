pub(super) const 四隅の数: usize = 4;
// 四隅が持つ法線の乗数。荷重の移し替えで負へ振れない大きさに置く(接線の乗数の合計の桁は1e-2である)。
const 四隅の法線の乗数の値: f32 = 0.05;

