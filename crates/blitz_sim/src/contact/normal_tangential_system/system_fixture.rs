//! 底面の四隅に接触点と錨を持つ剛体の連立を組む材料(判断12・判断13)。四隅は重心より半分の長さだけ下にあり、
//! 接線の力が重心まわりの回転を作る。面と面の接触の連立が階数の足りない形になることと、法線の荷重の移し替えが
//! 起きることの両方をこの配置が再現する。
//! 法線の乗数を正の値で置くのは、荷重の移し替えで乗数が負へ振れて有効集合から外れる点が出ないようにするためである。
//! 1点だけの連立は`single_point_fixture`が持つ。あちらは腕を零にして法線と接線の交差の項を厳密に零にする材料であり、
//! こちらは腕を持たせて交差の項を効かせる材料である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

