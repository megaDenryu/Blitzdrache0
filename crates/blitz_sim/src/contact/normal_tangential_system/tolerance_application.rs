use blitz_math::メートル;

use super::acceptance::残差と受理の許容差;
use super::tangential_row::錨の接線変位を零へ戻す一行;
use super::tolerance_candidate::{
    偽の固有値の下限を導く取り決め, 擬似逆が右辺の向きを捨てる判定の当て方, 解けたと見なす許容差を導く座標の由来
};
use super::tolerance_reach::{受理の倍率の届く先, 行を積む閾値の倍率};
use super::tolerance_scale::解けたと見なす許容差の倍率;

/// 接線の行へ許容差 δ を当てる先。行を積むかどうかと、積んだ行の右辺の2つが枝で決まる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 接線の行への許容差の当て方 {
    /// 改訂の前の本番(旧の形)。全部の点の行を積み、δ に受理の倍率を掛けて右辺へ残す。反証(4)(f)の対照である。
    右辺へ受理の倍率を掛けて残す,
    /// 全部の点の行を積み、δ を零にして右辺を −C_t にする(設計候補(i)。行を落とさない対照)。
    右辺を零にする,
    /// C_t の長さが δ の内側の点の行を積まず、積んだ行の右辺は −C_t にする(2026-09-12からの本番の形)。
    許容差の内側の点の行を積まず右辺を零にする,
}

/// 試験と計器が許容差を当てる指定。受理の倍率と、接線の行の右辺の δ の扱いと、段階A2の2つの候補の軸の組である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 試験の許容差の当て方 {
    受理の倍率: 解けたと見なす許容差の倍率,
    行への当て方: 接線の行への許容差の当て方,
    届く先: 受理の倍率の届く先,
    閾値の倍率: 行を積む閾値の倍率,
    右辺の向きを捨てる判定: 擬似逆が右辺の向きを捨てる判定の当て方,
    許容差の座標の由来: 解けたと見なす許容差を導く座標の由来,
    偽の固有値の下限の取り決め: 偽の固有値の下限を導く取り決め,
}

impl 試験の許容差の当て方 {
    /// 本番と同じ当て方(受理の倍率1倍・δ の内側の点の行を積まず右辺を −C_t)。この当て方を通した連立は本番と1ビットも違わない。
    pub fn 本番と同じ当て方() -> Self {
        Self::倍率と行への当て方から生成する(
            解けたと見なす許容差の倍率::既定で生成する(),
            接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする,
        )
    }

    /// 受理の倍率と行への当て方を名指しで組んだ当て方。段階A2の2つの候補の軸は本番の形で始まる。
    pub fn 倍率と行への当て方から生成する(
        受理の倍率: 解けたと見なす許容差の倍率, 行への当て方: 接線の行への許容差の当て方
    ) -> Self {
        Self {
            受理の倍率,
            行への当て方,
            届く先: 受理の倍率の届く先::擬似逆の採否と受理の判定,
            閾値の倍率: 行を積む閾値の倍率::既定で生成する(),
            右辺の向きを捨てる判定: 擬似逆が右辺の向きを捨てる判定の当て方::行ごとの許容差で捨てる,
            許容差の座標の由来: 解けたと見なす許容差を導く座標の由来::粗い位置の刻みから導く,
            偽の固有値の下限の取り決め: 偽の固有値の下限を導く取り決め::次数と機械イプシロンから導く,
        }
    }

    /// この当て方が接線の行へ許容差を当てる先。同じ配置へ別の候補を当てて勝った有効集合を比べる計器が読む。
    pub fn 行への当て方(&self) -> 接線の行への許容差の当て方 {
        self.行への当て方
    }

    /// この当て方で擬似逆の右辺の判定が何と比べるか(候補(α)と候補(θ)の軸)。抜き出した連立が解く前に読む。
    pub fn 右辺の向きを捨てる判定(&self) -> 擬似逆が右辺の向きを捨てる判定の当て方 {
        self.右辺の向きを捨てる判定
    }

    /// この当て方で擬似逆が偽の固有値と見なす下限をどう導くか(候補(η)の軸)。抜き出した連立が解く前に読む。
    pub fn 偽の固有値の下限の取り決め(&self) -> 偽の固有値の下限を導く取り決め {
        self.偽の固有値の下限の取り決め
    }

    /// この行を連立へ積むか。積まない枝では、呼び出し側がその点を接線変位が零の点として扱う。
    /// 比べる δ はその行の世界位置が表せる刻みであり、受理の倍率は掛けない。受理の δ は擬似逆が右辺の固有の
    /// 向きを捨てるときに比べる別の役目の値であり、行を積むかどうかの閾値と1つの値へ束ねると、倍率を振ったときに
    /// 何が動いたかを分けられなくなる。
    pub fn 接線の行を積むか(&self, 一行: &錨の接線変位を零へ戻す一行) -> bool {
        match self.行への当て方 {
            接線の行への許容差の当て方::右辺へ受理の倍率を掛けて残す | 接線の行への許容差の当て方::右辺を零にする => {
                true
            }
            接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする => {
                一行.接線変位の長さ().値() > self.閾値の倍率.比() * self.行の解けたと見なす許容差(一行.勾配()).値()
            }
        }
    }

    /// 行を積まなかった点について受理の判定(A)へ記す残差と閾値。閾値の帯 k δ の枝では閾値も k δ である(積まない判定と
    /// 同じ量で受理する)。本番と同じ当て方では C_t と δ そのものである。
    pub fn 積まなかった点の残差と閾値(&self, 一行: &錨の接線変位を零へ戻す一行) -> 残差と受理の許容差 {
        残差と受理の許容差::残差と許容差から生成する(
            一行.接線変位の長さ(),
            self.行の解けたと見なす許容差(一行.勾配()) * self.閾値の倍率.比(),
        )
    }

    /// この当て方での接線の行の連立の右辺。旧の形なら −(C_t − 倍率×δ)、それ以外は本番と同じ −C_t である。
    /// 前提: 行の接線変位の長さは正である(零の点は連立へ入らない)。
    pub fn 接線の行の右辺を求める(&self, 一行: &錨の接線変位を零へ戻す一行) -> メートル {
        match self.行への当て方 {
            接線の行への許容差の当て方::右辺へ受理の倍率を掛けて残す => {
                一行.許容差へ倍率を掛けた連立の右辺(self.受理の倍率)
            }
            接線の行への許容差の当て方::右辺を零にする | 接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする => {
                一行.連立の右辺()
            }
        }
    }
}
