//! 試験と計器が解けたと見なす許容差 δ をどう当てるかの指定(判断13、Issue #59の第4段階)。本番は常に
//! 「受理の倍率1倍・δ の内側の点の行を積まず右辺を −C_t・粗い位置の刻みから δ を導く・行ごとの許容差で右辺の向きを捨てる」
//! であり、それ以外を作れるのは試験と計器だけである。
//! δ が効く場所は3つある。接線の行を積むかどうかの閾値と、擬似逆が右辺の固有の向きを捨てるときに比べる行ごとの
//! 許容差(受理)と、混合連立の受理の判定である。改訂の前の本番(旧の形)は右辺 −(C_t − δ) の δ に受理の倍率を掛けていた。
//! 旧の形と、全部の点の行を積んで右辺だけを −C_t にする候補(i)は、判断13の反証(4)(f)の対照と段階A2・A3の計器の対照として残す。
//! 倍率と行への当て方と候補の2つの軸を1つの型に束ねるのは、これらが常に揃って連立へ渡るためである。閾値の δ には
//! 受理の倍率を掛けない。閾値の δ と受理の δ は役目が違い、束ねると倍率を振ったときに何が動いたかを分けられなくなるためである。
//! 別の当て方を組む口(`〜を差し替える`)は子モジュール`variants`が持つ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

