//! 試験と計器が解けたと見なす許容差 δ をどう当てるかの指定(判断13、Issue #59の第4段階の段階A2)。本番は常に
//! 「受理の倍率1倍・右辺の δ を残す」であり、それ以外を作れるのは試験と計器だけである。
//! δ が効く場所は2つある。接線の行の右辺 −(C_t − δ) の δ と、擬似逆が右辺の固有の向きを捨てるときに比べる
//! 行ごとの許容差(受理)である。段階A1までの倍率はこの2つへ同じ値を掛けていた。段階A2の計測(あ)は「右辺の δ を
//! 零にし、受理の δ だけを振る」ことを要るため、2つを別々に指定できる形へ広げた。倍率と右辺の扱いを1つの型に
//! 束ねるのは、この2つが常に揃って連立へ渡るためである。
//! 注意: 右辺の δ を零にすると相補条件を満たす有効集合が無い細分が増える(第1段階の観測4)。本番の経路へ入れてはならない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_math::メートル;

use super::tangential_row::錨の接線変位を零へ戻す一行;
use super::tolerance_scale::解けたと見なす許容差の倍率;

/// 接線の行の右辺 −(C_t − δ) の δ の扱い。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 接線の行の右辺の許容差の扱い {
    /// 本番と同じく、δ に受理の倍率を掛けて右辺へ残す。
    受理の倍率を掛けて残す,
    /// δ を零にし、右辺を −C_t にする(設計候補(i)の一次計測)。
    零にする,
}

/// 試験と計器が許容差を当てる指定。受理の倍率と、接線の行の右辺の δ の扱いの組である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 試験の許容差の当て方 {
    受理の倍率: 解けたと見なす許容差の倍率,
    右辺の扱い: 接線の行の右辺の許容差の扱い,
}

impl 試験の許容差の当て方 {
    /// 本番と同じ当て方(受理の倍率1倍・右辺の δ を残す)。この当て方を通した連立は本番と1ビットも違わない。
    pub fn 本番と同じ() -> Self {
        Self::受理の倍率だけを振る(解けたと見なす許容差の倍率::既定で生成する())
    }

    /// 段階A1までの計器と同じく、右辺の δ と受理の δ に同じ倍率を掛ける。
    pub fn 受理の倍率だけを振る(受理の倍率: 解けたと見なす許容差の倍率) -> Self {
        Self {
            受理の倍率,
            右辺の扱い: 接線の行の右辺の許容差の扱い::受理の倍率を掛けて残す,
        }
    }

    /// 右辺の δ を零にし、受理の δ だけに倍率を掛ける(段階A2の計測(あ))。
    pub fn 右辺の許容差を零にして受理は倍率で振る(受理の倍率: 解けたと見なす許容差の倍率) -> Self {
        Self {
            受理の倍率,
            右辺の扱い: 接線の行の右辺の許容差の扱い::零にする,
        }
    }

    /// 右辺の扱いはそのまま、受理の倍率だけを差し替えた当て方。同じ配置に別の倍率を当てて採否を比べる計器が読む。
    pub fn 受理の倍率を差し替える(&self, 受理の倍率: 解けたと見なす許容差の倍率) -> Self {
        Self { 受理の倍率, ..*self }
    }

    /// 擬似逆が右辺の固有の向きを捨てるときに比べる行ごとの許容差へ、受理の倍率を掛ける。
    pub fn 受理の許容差へ掛ける(&self, 許容差: メートル) -> メートル {
        self.受理の倍率.許容差へ掛ける(許容差)
    }

    /// この当て方での接線の行の連立の右辺。残すなら −(C_t − 倍率×δ)、零にするなら −C_t である。
    /// 前提: 行の接線変位の長さは正である(零の点は連立へ入らない)。
    pub fn 接線の行の右辺を求める(&self, 一行: &錨の接線変位を零へ戻す一行) -> メートル {
        match self.右辺の扱い {
            接線の行の右辺の許容差の扱い::受理の倍率を掛けて残す => {
                一行.許容差へ倍率を掛けた連立の右辺(self.受理の倍率)
            }
            接線の行の右辺の許容差の扱い::零にする => 一行.接線変位の長さ() * -1.0,
        }
    }

    /// 表の見出しに綴る形。
    pub fn 綴り(&self) -> String {
        let 右辺 = match self.右辺の扱い {
            接線の行の右辺の許容差の扱い::受理の倍率を掛けて残す => "右辺δ残す",
            接線の行の右辺の許容差の扱い::零にする => "右辺δ零",
        };
        format!("受理{}倍_{右辺}", self.受理の倍率.比())
    }
}
