//! 試験と計器が解けたと見なす許容差 δ をどう当てるかの指定(判断13、Issue #59の第4段階)。本番は常に
//! 「受理の倍率1倍・δ の内側の点の行を積まず右辺を −C_t」(2026-09-12の改訂)であり、それ以外を作れるのは試験と計器だけである。
//! δ が効く場所は2つある。接線の行を積むかどうかの閾値と、擬似逆が右辺の固有の向きを捨てるときに比べる行ごとの
//! 許容差(受理)である。改訂の前の本番(旧の形)は右辺 −(C_t − δ) の δ に受理の倍率を掛けていた。旧の形と、全部の点の行を
//! 積んで右辺だけを −C_t にする候補(i)は、判断13の反証(4)(f)の対照と段階A2・A3の計器の対照として残す。倍率と行への
//! 当て方を1つの型に束ねるのは、この2つが常に揃って連立へ渡るためである。閾値の δ には受理の倍率を掛けない。閾値の δ と
//! 受理の δ は役目が違い、束ねると倍率を振ったときに何が動いたかを分けられなくなるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

mod spelling;

use blitz_math::メートル;

use super::tangential_row::錨の接線変位を零へ戻す一行;
use super::tolerance_reach::{受理の倍率の届く先, 行を積む閾値の倍率};
use super::tolerance_scale::解けたと見なす許容差の倍率;

/// 接線の行へ許容差 δ を当てる先。行を積むかどうかと、積んだ行の右辺の2つが枝で決まる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 接線の行への許容差の当て方 {
    /// 改訂の前の本番(旧の形)。全部の点の行を積み、δ に受理の倍率を掛けて右辺へ残す。反証(4)(f)の対照である。
    右辺へ受理の倍率を掛けて残す,
    /// 全部の点の行を積み、δ を零にして右辺を −C_t にする(設計候補(i)。行を落とさない対照)。
    右辺を零にする,
    /// C_t の長さが δ の内側の点の行を積まず、積んだ行の右辺は −C_t にする(2026-09-12からの本番の形)。
    許容差の内側の点の行を積まず右辺を零にする,
}

/// 試験と計器が許容差を当てる指定。受理の倍率と、接線の行の右辺の δ の扱いの組である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 試験の許容差の当て方 {
    受理の倍率: 解けたと見なす許容差の倍率,
    行への当て方: 接線の行への許容差の当て方,
    届く先: 受理の倍率の届く先,
    閾値の倍率: 行を積む閾値の倍率,
}

impl 試験の許容差の当て方 {
    /// 本番と同じ当て方(受理の倍率1倍・δ の内側の点の行を積まず右辺を −C_t)。この当て方を通した連立は本番と1ビットも違わない。
    pub fn 本番と同じ当て方() -> Self {
        Self::倍率と行への当て方から生成する(
            解けたと見なす許容差の倍率::既定で生成する(),
            接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする,
        )
    }

    /// 受理の倍率と行への当て方を名指しで組んだ当て方。
    pub fn 倍率と行への当て方から生成する(
        受理の倍率: 解けたと見なす許容差の倍率, 行への当て方: 接線の行への許容差の当て方
    ) -> Self {
        Self {
            受理の倍率,
            行への当て方,
            届く先: 受理の倍率の届く先::擬似逆の採否と受理の判定,
            閾値の倍率: 行を積む閾値の倍率::既定で生成する(),
        }
    }

    /// 受理の倍率の届く先だけを差し替えた当て方。遠方の正接0.58の滑走が擬似逆の採否か受理の判定かを分ける計器が読む。
    pub fn 届く先を差し替える(&self, 届く先: 受理の倍率の届く先) -> Self {
        Self { 届く先, ..*self }
    }

    /// 行を積む閾値の倍率だけを差し替えた当て方。閾値の帯 k δ を測る計器が読む。
    pub fn 行を積む閾値の倍率を差し替える(&self, 閾値の倍率: 行を積む閾値の倍率) -> Self {
        Self { 閾値の倍率, ..*self }
    }

    /// 旧の形(改訂の前の本番)のまま、右辺の δ と受理の δ に同じ倍率を掛ける。段階A1までの計器と反証(4)(f)の対照が読む。
    pub fn 受理の倍率だけを振る(受理の倍率: 解けたと見なす許容差の倍率) -> Self {
        Self::倍率と行への当て方から生成する(受理の倍率, 接線の行への許容差の当て方::右辺へ受理の倍率を掛けて残す)
    }

    /// 行への当て方はそのまま、受理の倍率だけを差し替えた当て方。同じ配置に別の倍率を当てて採否を比べる計器が読む。
    pub fn 受理の倍率を差し替える(&self, 受理の倍率: 解けたと見なす許容差の倍率) -> Self {
        Self { 受理の倍率, ..*self }
    }

    /// 受理の倍率はそのまま、行への当て方だけを差し替えた当て方。同じ配置に別の候補を当てて勝った有効集合を比べる
    /// 計器が読む。
    pub fn 行への当て方を差し替える(&self, 行への当て方: 接線の行への許容差の当て方) -> Self {
        Self { 行への当て方, ..*self }
    }

    /// この当て方が接線の行へ許容差を当てる先。同じ配置へ別の候補を当てて勝った有効集合を比べる計器が読む。
    pub fn 行への当て方(&self) -> 接線の行への許容差の当て方 {
        self.行への当て方
    }

    /// 擬似逆が右辺の固有の向きを捨てるときに比べる行ごとの許容差へ、受理の倍率を掛ける。届く先が受理の判定だけなら掛けない。
    pub fn 受理の許容差へ掛ける(&self, 許容差: メートル) -> メートル {
        match self.届く先 {
            受理の倍率の届く先::擬似逆の採否と受理の判定 => self.受理の倍率.許容差へ掛ける(許容差),
            受理の倍率の届く先::受理の判定だけ => 許容差,
        }
    }

    /// 受理の判定(A・B1・B4)が比べる許容差へ掛ける倍率。擬似逆の側で既に掛けた当て方では掛けない(二重に掛けない)。
    pub fn 受理の判定の許容差へ掛ける(&self, 許容差: メートル) -> メートル {
        match self.届く先 {
            受理の倍率の届く先::擬似逆の採否と受理の判定 => 許容差,
            受理の倍率の届く先::受理の判定だけ => self.受理の倍率.許容差へ掛ける(許容差),
        }
    }

    /// この行を連立へ積むか。積まない枝では、呼び出し側がその点を接線変位が零の点として扱う。
    /// 比べる δ はその行の世界位置が表せる刻みであり、受理の倍率は掛けない。受理の δ は擬似逆が右辺の固有の
    /// 向きを捨てるときに比べる別の役目の値であり、行を積むかどうかの閾値と1つの値へ束ねると、倍率を振ったときに
    /// 何が動いたかを分けられなくなる。
    pub fn 接線の行を積むか(&self, 一行: &錨の接線変位を零へ戻す一行) -> bool {
        match self.行への当て方 {
            接線の行への許容差の当て方::右辺へ受理の倍率を掛けて残す | 接線の行への許容差の当て方::右辺を零にする => {
                true
            }
            接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする => {
                一行.接線変位の長さ().値() > self.閾値の倍率.比() * 一行.勾配().解けたと見なす許容差().値()
            }
        }
    }

    /// この当て方での接線の行の連立の右辺。旧の形なら −(C_t − 倍率×δ)、それ以外は本番と同じ −C_t である。
    /// 前提: 行の接線変位の長さは正である(零の点は連立へ入らない)。
    pub fn 接線の行の右辺を求める(&self, 一行: &錨の接線変位を零へ戻す一行) -> メートル {
        match self.行への当て方 {
            接線の行への許容差の当て方::右辺へ受理の倍率を掛けて残す => {
                一行.許容差へ倍率を掛けた連立の右辺(self.受理の倍率)
            }
            接線の行への許容差の当て方::右辺を零にする | 接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする => {
                一行.連立の右辺()
            }
        }
    }
}
