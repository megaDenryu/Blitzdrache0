//! 抜き出した連立が擬似逆へ渡す2つの入力を答える工程(判断12・判断13)。2つとは、右辺の固有の向きを捨てる判定が
//! 行ごとに比べる許容差 δ_i と、偽の固有値と見なす固有値の下限である。
//! 抜き出し(`reduced_system`)から分けているのは、あちらが対称行列と右辺と許容差を組み立てる工程であり、こちらが
//! 「組み立てた値のうち擬似逆へどれを渡すか」だけを答える工程だからである。触れるフィールドは、行ごとの解けたと
//! 見なす許容差と、試験の構成だけが持つ2つの候補の軸に限られる。
//! 本番の構成は候補の軸の型を知らず、組み立てた許容差と分解そのものの下限をそのまま渡す。試験の構成だけが、
//! 候補(α)(何とも比べない)・候補(θ)(接線の雑音の床へ安全率を掛けた1つの長さで比べる)・候補(η)(最大の固有値への
//! 相対比で下限を置く)の枝を選べる。本番と同じ適用規則なら答えは本番と1ビットも違わない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::super::symmetric_system::{対称な連立の固有分解, 法線と接線の連立の行の上限};
use super::reduced_system::有効な行だけを抜き出した連立;
#[cfg(test)]
use super::tolerance_candidate::偽の固有値の下限を導く取り決め;

impl 有効な行だけを抜き出した連立 {
    /// 擬似逆の右辺の判定が比べる行ごとの許容差。本番は組み立てた許容差そのものである。
    #[cfg(not(test))]
    pub(super) fn 擬似逆が比べる行ごとの許容差(&self) -> &[f32; 法線と接線の連立の行の上限] {
        &self.行ごとの解けたと見なす許容差
    }

    /// 同じ口の試験の構成。候補(α)と候補(θ)が差し替えた値を`reduced_system_tolerance_scale`が既に埋めてある。
    #[cfg(test)]
    pub(super) fn 擬似逆が比べる行ごとの許容差(&self) -> &[f32; 法線と接線の連立の行の上限] {
        &self.擬似逆の右辺の判定が比べる行ごとの許容差
    }

    /// 擬似逆が偽の固有値と見なす固有値の下限。本番は分解そのものの丸めが作る下限 λ_max n ε である。
    #[cfg(not(test))]
    pub(super) fn 擬似逆が偽の固有値と見なす下限(&self, 分解: &対称な連立の固有分解) -> f32 {
        分解.偽の固有値の下限()
    }

    /// 同じ口の試験の構成。候補(η)の取り決めだけが、最大の固有値への相対比から下限を置く。
    #[cfg(test)]
    pub(super) fn 擬似逆が偽の固有値と見なす下限(&self, 分解: &対称な連立の固有分解) -> f32 {
        match self.偽の固有値の下限の取り決め {
            偽の固有値の下限を導く取り決め::次数と機械イプシロンから導く => 分解.偽の固有値の下限(),
            偽の固有値の下限を導く取り決め::最大の固有値への相対比から導く { 相対比 } => {
                分解.固有値の最大() * 相対比
            }
        }
    }
}
