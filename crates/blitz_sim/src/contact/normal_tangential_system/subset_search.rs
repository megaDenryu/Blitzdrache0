//! 法線の相補条件を満たす有効集合を、有効な点の数が多い階層から順に走査して探す工程(判断12・判断13)。
//! 連立の定義(`system`)から分けているのは、行を積むのが接触点集合の走査1回であるのに対し、この工程が抜き出しと
//! 求解を部分集合の数だけ繰り返す別の局面だからである。
//! 組み替えの向きを順に選んで枢軸を動かす形を採らないのは、外す条件と入れ直す条件が同じ点について同時に成り立つ
//! 材料が坂の場面に実在し、組み替えが巡回して解が定まらないためである(600刻みの正接0.50で50件観測した)。
//! 階層で打ち切るのは、決着の第1の鍵が有効な点の数であるためである(`candidate`)。ある階層で相補条件を満たす候補が
//! 1つでも見つかれば、それより点の数が少ない階層の候補は決着で必ず負けるため、下の階層を解く必要が無い。
//! したがって階層の走査が返す候補は、全部の部分集合を走査して選んだ候補と1ビットも変わらない。その一致は
//! 試験専用の正典(`full_scan_reference`)との突き合わせが固定する。
//! 部分集合の枚挙そのものはビット演算だけであり、費用が掛かるのは1つの部分集合ごとの抜き出しと求解である。
//! 階層ごとに枚挙をやり直しているのは、立っているビットの数の順に部分集合を直に並べる形より読みが単純であり、
//! 枚挙の費用が求解の費用に対して無視できるためである。
//! 接触点の上限が8であるため部分集合は高々256個であり、有限の時間と終了が表し方から保証できる。
//! 正しさの基準となるCPUの参照計算はこの形を採り、GPUの実装が別の探し方を採るときはこの結果を正典として比べる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::active_set::法線と接線の連立の有効集合;
use super::candidate::相補条件を満たした候補;
use super::reduced_system::有効な行だけを抜き出した連立;
use super::solve_outcome::相補条件を満たす有効集合を探した結末;
use super::system::接触点集合の法線と接線の連立;

impl 接触点集合の法線と接線の連立 {
    /// 有効な点の数が多い階層から順に部分集合を調べ、相補条件を満たす候補が見つかった階層で打ち切って、
    /// その階層の中で決着の順で先に来る1つを解として返す。
    pub fn 相補条件を満たす有効集合で同時に解く(&self) -> 相補条件を満たす有効集合を探した結末 {
        match self.点の数の多い階層から順に候補を探す() {
            None => 相補条件を満たす有効集合を探した結末::相補条件を満たす有効集合が無い,
            Some(候補) if !候補.全部の行の残差が許容差の内側か() => {
                相補条件を満たす有効集合を探した結末::表現の精度が不足した
            }
            Some(候補) => 相補条件を満たす有効集合を探した結末::有効集合が定まった(候補.同時解()),
        }
    }

    // 有効な点の数が多い階層から順に見て、候補が1つ以上見つかった最初の階層の勝者を返す。
    pub(super) fn 点の数の多い階層から順に候補を探す(&self) -> Option<相補条件を満たした候補> {
        let 入れてよい点 = self.有効集合へ入れてよい点の集合();
        (0..=入れてよい点.点の数を数える())
            .rev()
            .find_map(|階層の点の数| self.一つの階層で先に選ぶ候補を探す(入れてよい点, 階層の点の数))
    }

    // 含む点の数が指定の値である部分集合だけを解き、その中で決着の順で先に来る1つを返す。
    fn 一つの階層で先に選ぶ候補を探す(
        &self,
        入れてよい点: 法線と接線の連立の有効集合,
        階層の点の数: usize,
    ) -> Option<相補条件を満たした候補> {
        let mut 先に選ぶ候補: Option<相補条件を満たした候補> = None;
        let mut 部分集合 = 入れてよい点;
        loop {
            if 部分集合.点の数を数える() == 階層の点の数
                && let Some(候補) = self.一つの部分集合を候補にする(部分集合)
            {
                先に選ぶ候補 = Some(match 先に選ぶ候補 {
                    Some(前の候補) => 前の候補.先に選ぶ方を採る(候補),
                    None => 候補,
                });
            }
            if 部分集合.一点も含まないか() {
                break;
            }
            部分集合 = 部分集合.全体の中で次に小さい部分集合(&入れてよい点);
        }
        先に選ぶ候補
    }

    // 1つの部分集合を解き、相補条件を満たすなら候補にする。満たさない集合は無しを返す。
    pub(super) fn 一つの部分集合を候補にする(
        &self, 有効集合: 法線と接線の連立の有効集合
    ) -> Option<相補条件を満たした候補> {
        let 抜き出した = 有効な行だけを抜き出した連立::抜き出す(self, &有効集合);
        let 解 = 抜き出した.解く();
        let 同時解 = 抜き出した.もとの点へ戻す(&解, self, &有効集合);
        if !self.相補条件を満たすか(&同時解, &有効集合) {
            return None;
        }
        Some(相補条件を満たした候補::解と質と有効集合から組む(
            同時解,
            抜き出した.解いた行の残差と補正の大きさを測る(&解),
            有効集合,
        ))
    }
}
