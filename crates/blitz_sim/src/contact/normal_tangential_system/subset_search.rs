//! 法線の相補条件を満たす有効集合を、取りうる部分集合を全部走査して探す工程(判断12・判断13)。
//! 連立の定義(`system`)から分けているのは、行を積むのが接触点集合の走査1回であるのに対し、この工程が抜き出しと
//! 求解を部分集合の数だけ繰り返す別の局面だからである。
//! 組み替えの向きを順に選んで枢軸を動かす形を採らないのは、外す条件と入れ直す条件が同じ点について同時に成り立つ
//! 材料が坂の場面に実在し、組み替えが巡回して解が定まらないためである(600刻みの正接0.50で50件観測した)。
//! 接触点の上限が8であるため部分集合は高々256個であり、全部を調べても有限の時間と終了が表し方から保証できる。
//! 正しさの基準となるCPUの参照計算はこの形を採り、GPUの実装が別の探し方を採るときはこの結果を正典として比べる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::active_set::法線と接線の連立の有効集合;
use super::candidate::相補条件を満たした候補;
use super::reduced_system::有効な行だけを抜き出した連立;
use super::solution::接触点集合の法線と接線の同時解;
use super::solve_outcome::相補条件を満たす有効集合を探した結末;
use super::system::接触点集合の法線と接線の連立;
use crate::rigid_xpbd::姿勢自由度の補正;

impl 接触点集合の法線と接線の連立 {
    /// 取りうる有効集合を全部調べ、相補条件を満たす候補のうち決着の順で先に来る1つを解として返す。
    pub fn 相補条件を満たす有効集合で同時に解く(&self) -> 相補条件を満たす有効集合を探した結末 {
        let 候補のビット並び = self.有効集合へ入れてよい点のビット並び();
        let mut 先に選ぶ候補: Option<相補条件を満たした候補> = None;
        let mut ビット並び = 候補のビット並び;
        loop {
            if let Some(候補) = self.一つの部分集合を候補にする(ビット並び) {
                先に選ぶ候補 = Some(match 先に選ぶ候補 {
                    Some(前の候補) => 前の候補.先に選ぶ方を採る(候補),
                    None => 候補,
                });
            }
            if ビット並び == 0 {
                break;
            }
            ビット並び = (ビット並び - 1) & 候補のビット並び;
        }
        match 先に選ぶ候補 {
            None => 相補条件を満たす有効集合を探した結末::相補条件を満たす有効集合が無い,
            Some(候補) if !候補.全部の行の残差が許容差の内側か() => {
                相補条件を満たす有効集合を探した結末::表現の精度が不足した
            }
            Some(候補) => 相補条件を満たす有効集合を探した結末::有効集合が定まった(候補.同時解()),
        }
    }

    /// 求めた増分が剛体(第1の参加者)へ与える補正の合計。点ごとに配置へ適用すると次の点の腕と有効逆質量が
    /// 変わるため、呼び出し側はこの合計を1度だけ適用する。
    pub fn 第1の参加者への補正の合計(&self, 同時解: &接触点集合の法線と接線の同時解) -> 姿勢自由度の補正 {
        let mut 合計 = 姿勢自由度の補正::零();
        for 点の番号 in 0..self.点の数() {
            if let Some(法線の行) = self.法線の一行を読む(点の番号) {
                let 増分 = 同時解.一点の法線の乗数の増分(点の番号);
                合計 = 合計.合わせる(&法線の行.勾配().乗数の増分を第1の参加者の補正へ分配する(増分));
            }
            if let Some(接線の行) = self.接線の一行を読む(点の番号) {
                let 増分 = 同時解.一点の接線の乗数の増分(点の番号);
                合計 = 合計.合わせる(&接線の行.勾配().乗数の増分を第1の参加者の補正へ分配する(増分));
            }
        }
        合計
    }

    // 1つの部分集合を解き、相補条件を満たすなら候補にする。満たさない集合は無しを返す。
    fn 一つの部分集合を候補にする(&self, ビット並び: u8) -> Option<相補条件を満たした候補> {
        let 有効集合 = 法線と接線の連立の有効集合::ビット並びから生成する(ビット並び);
        let 抜き出した = 有効な行だけを抜き出した連立::抜き出す(self, &有効集合);
        let 解 = 抜き出した.解く();
        let 同時解 = 抜き出した.もとの点へ戻す(&解, self, &有効集合);
        if !self.相補条件を満たすか(&同時解, &有効集合) {
            return None;
        }
        Some(相補条件を満たした候補::解と質とビット並びから組む(
            同時解,
            抜き出した.解いた行の残差と補正の大きさを測る(&解),
            有効集合.ビット並び(),
        ))
    }
}
