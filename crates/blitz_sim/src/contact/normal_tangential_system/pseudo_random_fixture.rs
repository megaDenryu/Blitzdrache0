//! 反証が使う、種から決まった並びを進む擬似乱数。同じ種からは必ず同じ並びが出る。
//! 法線と接線の連立のモジュールに置くのは、いまこの並びを読むのが同じモジュールの無作為な材料の生成元だけで
//! あるためである。別のモジュールの反証も読むようになった日に、接触の層の根へ上げる。
//!
//! 外部の乱数の実装を持ち込まないのは、反証が落ちたときにどの入力で落ちたかを種だけで再現できるようにするためで
//! ある。実装は線形合同法であり、統計的な質は要らない。要るのは、材料の値を広く散らすことだけである。
//!
//! 生の値を`as`で変換せず、上位のビットを取り出してから整数の変換で単精度へ写すのは、数値の`as`キャストが
//! 規約で禁じられているためである。

#![cfg(test)]

// 線形合同法の乗数と加数。よく知られた組であり、周期は2の64乗である。
const 乗数: u64 = 6_364_136_223_846_793_005;
const 加数: u64 = 1_442_695_040_888_963_407;

pub(super) struct 決まった種から進む擬似乱数 {
    状態: u64,
}

impl 決まった種から進む擬似乱数 {
    pub(super) fn 種から始める(種: u64) -> Self {
        Self { 状態: 種 }
    }

    // 上位16ビットを取り出した整数。単精度の値を組む反証が読む。
    fn 次の16ビットの整数(&mut self) -> u16 {
        self.状態 = self.状態.wrapping_mul(乗数).wrapping_add(加数);
        let [上位, 下位, ..] = self.状態.to_be_bytes();
        u16::from_be_bytes([上位, 下位])
    }

    /// 下限以上上限未満の単精度の値。
    pub(super) fn 範囲の中の単精度の値(&mut self, 下限: f32, 上限: f32) -> f32 {
        下限 + (上限 - 下限) * (f32::from(self.次の16ビットの整数()) / 65_536.0)
    }
}
