//! 通った有効集合の記録の試験(判断12・判断13)。担当するのは、同じ集合を2度目に渡すと初めてでないと答えること、
//! 別々の集合を混同しないこと、取りうる全部の集合を印しても混同が起きないことを固定することである。
//! これが、有効集合の組み替えが高々256回で新しい集合を作れなくなること、つまり組み替えが必ず終わることの根拠である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

#![allow(clippy::unwrap_used)]

use blitz_collision::contact_set::接触点の上限;

use super::active_set::法線と接線の連立の有効集合;
use super::visited_active_set::通った有効集合の記録;

// 第k番のビットが立っている番号の点だけを入れた集合。
fn ビット並びから集合を組む(ビット並び: usize) -> 法線と接線の連立の有効集合 {
    let mut 集合 = 法線と接線の連立の有効集合::空();
    for 点の番号 in 0..接触点の上限 {
        if ビット並び & (1 << 点の番号) != 0 {
            集合.入れる(点の番号);
        }
    }
    集合
}

#[test]
fn 同じ有効集合を二度渡すと二度目は初めてでないと答える() {
    let mut 記録 = 通った有効集合の記録::空();
    let 集合 = ビット並びから集合を組む(0b1011);
    assert!(記録.初めて通るなら印す(&集合), "一度目が初めてでないと答えた");
    assert!(!記録.初めて通るなら印す(&集合), "二度目が初めてだと答えた");
}

#[test]
fn 取りうる全部の有効集合を印しても混同しない() {
    let 取りうる状態の数 = 1 << 接触点の上限;
    let mut 記録 = 通った有効集合の記録::空();
    for ビット並び in 0..取りうる状態の数 {
        assert!(
            記録.初めて通るなら印す(&ビット並びから集合を組む(ビット並び)),
            "まだ通っていない集合を通ったと答えた: {ビット並び}"
        );
    }
    for ビット並び in 0..取りうる状態の数 {
        assert!(
            !記録.初めて通るなら印す(&ビット並びから集合を組む(ビット並び)),
            "通った集合を初めてだと答えた: {ビット並び}"
        );
    }
}
