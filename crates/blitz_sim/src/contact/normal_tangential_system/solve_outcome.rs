//! 有効集合を組み替えながら解いた結末(判断12・判断13)。求解の工程(`system_solve`)から分けているのは、
//! こちらが工程が返す値の形であり、あちらがその値を作る工程だからである。
//! 巡回を枝として持つのは、組み替えが行を外す向きと入れ直す向きの両方を持ち、同じ点が何度も出入りしうるためである。
//! 最後の解を正常な値として無言で返してはならない。円錐の判定はこの解が作る乗数だけで行われ、定まらない解で
//! 判定すると、保持できる集合を滑走中と印す誤りが静かに残る。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::solution::接触点集合の法線と接線の同時解;

/// 有効集合を組み替えながら解いた結末。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 有効集合を組み替えて解いた結末 {
    /// 組み替えが止まり、終わりの再検査を通った解である。
    有効集合が定まった(接触点集合の法線と接線の同時解),
    /// 一度通った有効集合へ戻った。この材料では組み替えが止まらず、解が定まらない。
    有効集合の組み替えが巡回した,
}

impl 有効集合を組み替えて解いた結末 {
    /// 定まった解。前提: この結末が定まった枝であることを呼び出し側が知っている。
    /// 注意: 材料を固定した試験と計器だけの口である。本番の呼び出し側は2つの枝を場合分けする。
    #[cfg(test)]
    pub fn 定まった解を取り出す(&self) -> 接触点集合の法線と接線の同時解 {
        match self {
            Self::有効集合が定まった(同時解) => *同時解,
            Self::有効集合の組み替えが巡回した => panic!("有効集合の組み替えが巡回したため解が定まっていない"),
        }
    }
}
