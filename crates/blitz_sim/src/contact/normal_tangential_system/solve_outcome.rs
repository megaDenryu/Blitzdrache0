//! 相補条件を満たす有効集合を探した結末(判断12・判断13)。探す工程(`subset_search`)から分けているのは、
//! こちらが工程が返す値の形であり、あちらがその値を作る工程だからである。
//! 解けなかった2つを枝として持つのは、最後に見た解を正常な値として無言で返してはならないためである。円錐の判定は
//! この解が作る乗数だけで行われ、定まらない解や要求の精度で解けていない解で判定すると、保持できる集合を滑走中と
//! 印す誤りが静かに残る。
//! 「表現の精度が不足した」を別の枝にするのは、相補条件そのものは満たすのに右辺を要求の精度で閉じられない配置が
//! あるためである。世界の原点から遠い場面では、法線の行の許容差が座標の表現の刻みまで粗くなる一方で接線の行の
//! 許容差は細かいままであり、接線の行の残差だけが許容差を超える。この状態を粘着の成功として扱ってはならない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::solution::接触点集合の法線と接線の同時解;

/// 相補条件を満たす有効集合を全部の部分集合から探した結末。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 相補条件を満たす有効集合を探した結末 {
    /// 相補条件を満たし、全部の行の残差が許容差の内側に収まる解が定まった。
    有効集合が定まった(接触点集合の法線と接線の同時解),
    /// どの部分集合も相補条件を満たさなかった。この材料では粘着の候補が定まらない。
    相補条件を満たす有効集合が無い,
    /// 相補条件は満たすが、どの候補も行の残差を許容差の内側へ収められなかった。
    表現の精度が不足した,
}

impl 相補条件を満たす有効集合を探した結末 {
    /// 定まった解。前提: この結末が定まった枝であることを呼び出し側が知っている。
    /// 注意: 材料を固定した試験と計器だけの口である。本番の呼び出し側は3つの枝を場合分けする。
    #[cfg(test)]
    pub fn 定まった解を取り出す(&self) -> 接触点集合の法線と接線の同時解 {
        match self {
            Self::有効集合が定まった(同時解) => *同時解,
            Self::相補条件を満たす有効集合が無い => panic!("相補条件を満たす有効集合が無いため解が定まっていない"),
            Self::表現の精度が不足した => panic!("表現の精度が不足したため解が定まっていない"),
        }
    }
}
