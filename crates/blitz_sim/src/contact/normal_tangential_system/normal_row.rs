//! 法線と接線の連立の法線の1行(判断12・判断13)。非貫通を解き終えた配置で、接線の補正がその隔たりを動かさない
//! ことを求める行である。右辺が零であるのは、この段が解くのが荷重の移し替えだけであり、貫通の解消は判断12の
//! 連立が既に終えているからである。
//! 接線だけを解くと、接触点に働く接線の力が重心まわりの回転を含む補正を作り、次の反復の非貫通がその回転を戻して
//! 錨の接線変位を作り直す。接線の乗数はその作り直された変位に対してもう一度積まれ、円錐を超える(実測は
//! `_doc/計測/剛体の接触の摩擦と反発_2026-09-03.md`)。法線の行を同じ行列へ入れると、回転を打ち消す荷重の
//! 移し替えが接線の増分と同時に決まる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

use blitz_math::{メートル, ワールド, 方向};

use super::super::contact_projection_participant::接触の射影に参加する点;
use super::row_gradient::一行の二つの符号付き勾配;
use crate::xpbd::ラグランジュ乗数;

/// 接触点1つの、法線の隔たりを動かさないことを求める行。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 法線の隔たりを動かさない一行 {
    勾配: 一行の二つの符号付き勾配,
    隔たり: メートル,
    既存の法線の乗数: ラグランジュ乗数,
}

impl 法線の隔たりを動かさない一行 {
    /// この反復の接触点と、判断12が積んだ法線の乗数から作る。接触法線は第1の参加者から第2の参加者へ向かう向きである。
    pub fn 接触点と法線の乗数から生成する(
        第1の接触点: 接触の射影に参加する点,
        第2の接触点: 接触の射影に参加する点,
        接触法線: 方向<ワールド>,
        既存の法線の乗数: ラグランジュ乗数,
    ) -> Self {
        Self {
            勾配: 一行の二つの符号付き勾配::法線の行として生成する(第1の接触点, 第2の接触点, 接触法線),
            隔たり: (第2の接触点.世界位置() - 第1の接触点.世界位置()).方向に沿う長さ(接触法線),
            既存の法線の乗数,
        }
    }

    pub fn 勾配(&self) -> &一行の二つの符号付き勾配 {
        &self.勾配
    }

    /// いまの配置での法線方向の隔たり d = (p_2 − p_1)·n。負が貫通である。
    pub fn 隔たり(&self) -> メートル {
        self.隔たり
    }

    /// この細分で判断12が積んだ法線のラグランジュ乗数。有効集合から外れた行はこの値を零へ解放する。
    pub fn 既存の法線の乗数(&self) -> ラグランジュ乗数 {
        self.既存の法線の乗数
    }

    /// 連立の右辺。隔たりを動かさないことを求めるため零である。
    pub fn 連立の右辺(&self) -> メートル {
        メートル::生成する(0.0)
    }

    /// この行が有効集合の開始の集合に入るか。判断12の開始の定義と同じく、押し戻している行だけを入れる。
    pub fn 押し戻しているか(&self) -> bool {
        let 押し戻している = self.表現の刻みを超えて食い込むか(self.隔たり) || self.既存の法線の乗数 > ラグランジュ乗数::零();
        押し戻している && !self.勾配.動かせない組か()
    }

    /// 渡した隔たりが、この行の世界位置が表せる刻みを超えて負であるか。有効集合へ入れ直す判定が読む。
    /// 刻みを下限に置くのは、それを下回る隔たりを補正で閉じられないためである。
    pub fn 表現の刻みを超えて食い込むか(&self, 隔たり: メートル) -> bool {
        隔たり < self.勾配.右辺の丸めの大きさ() * -1.0
    }
}
