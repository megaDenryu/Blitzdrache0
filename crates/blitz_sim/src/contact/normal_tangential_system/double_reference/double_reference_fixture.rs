//! 単精度と倍精度を突き合わせる試験が共有する材料(Issue #59)。
//! 材料は腕を持つ接触点1つである。面と面の4点では連立の階数が足りず、どの乗数でも満たせない成分が差へ混ざる。
//! その成分は座標を倍精度にしても消えないため、2つの経路の一致を見る材料には使えない。
//! 材料の長さを2の冪にするのは、単精度でも倍精度でも同じ値を正確に表せるようにして、入力の丸めを差から
//! 除くためである。残る差は演算の丸めだけになる。
//! 参照計算を`単精度の許容差を据え置く`由来で回すのは、この試験が写し違いを見るものだからである。倍精度の
//! 刻みから導いた許容差で回すと、差に許容差の効果が混ざり、写しが同じ式であることを判定できない。
//! 倍精度の刻みから導いた列は診断の表が別に綴る。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

