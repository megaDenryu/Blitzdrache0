const 底面の半分の長さ: f32 = 0.5;
// 初めの食い込みと錨のずらし。2の冪を除算で綴るのは、十進の綴りだと単精度の有効数字を超えるためである。
const 初めの食い込み: f32 = 1.0 / 8192.0;
const 錨をずらす長さ: f32 = 1.0 / 1024.0;

pub(super) fn 試験の質量特性() -> 質量特性 {
    質量特性を作る(1.0, 1.0)
}

/// 重心の下に接触点を持ち、錨だけを接平面の中でずらした接触点1つ。
pub(super) fn 錨をずらした接触点一つ() -> (剛体と静的世界の接触拘束, 配置) {
    let 配置 = 配置::生成する(世界の位置を作る(0.0, -初めの食い込み, 0.0), 姿勢::恒等());
    let 引数 = 剛体と静的世界の接触拘束の引数 {
        剛体側の局所接触点: 局所の変位を作る(0.0, -底面の半分の長さ, 0.0),
        静的世界側の接触点: 世界の位置を作る(0.0, -底面の半分の長さ, 0.0),
        ..剛体と静的世界の基本の引数()
    };
    let mut 拘束 = 剛体と静的世界の接触拘束::引数と刻み幅から生成する(引数, 試験の刻み幅()).unwrap();
    拘束.開始した接触の錨を予測の前の配置へ置く(&配置::生成する(
        世界の位置を作る(錨をずらす長さ, -初めの食い込み, 0.0),
        姿勢::恒等(),
    ));
    (拘束, 配置)
}

/// 単精度の本番の経路で同じ1点の連立を組む。行の積み方は本番の細分の工程と同じ2つの口を読む。
pub(super) fn 単精度の連立を組む(
    拘束: &剛体と静的世界の接触拘束, 配置: &配置
) -> 接触点集合の法線と接線の連立 {
    let 参加者 = 姿勢自由度の参加者::動的(*配置, &試験の質量特性());
    let mut 連立 = 接触点集合の法線と接線の連立::点の数から空で始める(1);
    拘束.法線と接線の連立へ法線の一行を積む(0, &mut 連立, &参加者);
    拘束.法線と接線の連立へ接線の一行を積む(0, &mut 連立, &参加者);
    連立
}

/// 単精度の許容差を据え置いた倍精度の参照計算の解。定まらなければ試験の材料の不備である。
pub(super) fn 許容差を据え置いた倍精度の解(拘束: 剛体と静的世界の接触拘束, 配置: &配置) -> 倍精度の参照の解 {
    let 結末 = 倍精度の参照の結末::単精度の接触点集合から求める(
        &[拘束],
        配置,
        &試験の質量特性(),
        参照計算の許容差の由来::単精度の許容差を据え置く,
    );
    match 結末 {
        倍精度の参照の結末::解が定まった(解) => *解,
        _ => panic!("倍精度の参照計算が接触点1つの材料で解を定められなかった: {}", 結末.結末の綴り()),
    }
}
