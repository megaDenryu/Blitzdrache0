//! 倍精度の、接触点集合の法線と接線を同時に解いた結果(Issue #59の数値契約の診断)。単精度の
//! `接触点集合の法線と接線の同時解`と同じ3つ(点ごとの法線の乗数の増分・接線の乗数の増分・法線の行が有効か)を持つ。
//! 連立の型から分けているのは、こちらが解いた後に凍る値であり、連立が行を積むあいだ書き換わる状態を所有するからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_collision::contact_set::接触点の上限;

/// 倍精度の、接触点集合1つの法線と接線を同時に解いた結果。並びは接触点集合の中の点の番号と同じである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 倍精度の接触点集合の同時解 {
    法線の乗数の増分: [f64; 接触点の上限],
    接線の乗数の増分: [f64; 接触点の上限],
    法線の行が有効か: [bool; 接触点の上限],
}

impl 倍精度の接触点集合の同時解 {
    pub(in crate::contact) fn 空() -> Self {
        Self {
            法線の乗数の増分: [0.0; 接触点の上限],
            接線の乗数の増分: [0.0; 接触点の上限],
            法線の行が有効か: [false; 接触点の上限],
        }
    }

    pub(in crate::contact) fn 一点の解を書き込む(
        &mut self,
        点の番号: usize,
        法線の乗数の増分: f64,
        接線の乗数の増分: f64,
        法線の行が有効か: bool,
    ) {
        self.法線の乗数の増分[点の番号] = 法線の乗数の増分;
        self.接線の乗数の増分[点の番号] = 接線の乗数の増分;
        self.法線の行が有効か[点の番号] = 法線の行が有効か;
    }

    /// 指定の点の法線の乗数の増分 Δλ_n。有効集合から外れた点は乗数を零へ解放する値である。
    pub(in crate::contact) fn 一点の法線の乗数の増分(&self, 点の番号: usize) -> f64 {
        self.法線の乗数の増分[点の番号]
    }

    /// 指定の点の接線の乗数の増分 Δs。連立へ入らなかった点は零である。
    pub(in crate::contact) fn 一点の接線の乗数の増分(&self, 点の番号: usize) -> f64 {
        self.接線の乗数の増分[点の番号]
    }

    /// 指定の点の法線の行が有効集合に残ったか。偽の点は接線の乗数を零へ解放する。
    pub(in crate::contact) fn 一点の法線の行が有効か(&self, 点の番号: usize) -> bool {
        self.法線の行が有効か[点の番号]
    }
}
