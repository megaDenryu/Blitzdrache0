//! 倍精度の剛体の配置(Issue #59の数値契約の診断)。重心の世界位置と姿勢の単位四元数を倍精度で持ち、重心局所の
//! 点を世界へ写す。単精度の`配置`が`glam`で行う写しと同じ式を倍精度で書き直したものである。
//! ベクトル(`vector`)から分けているのは、こちらが回転という向きを持つ写しを所有し、あちらが成分の代数だけを
//! 持つからである。回転の式に四元数の積を使わず「v + 2w(u × v) + 2u × (u × v)」を直に書くのは、四元数の積の
//! 型と綴りを増やさずに同じ回転が得られるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断9: 拘束の勾配から並進と回転の補正を一般化逆質量で分配し、確定後に速度と角速度を再構成する」

#![cfg(test)]

use blitz_math::{クォータニオン, 空間};

use super::vector::倍精度の三次元ベクトル;
use crate::rigid_body::配置;

/// 倍精度の剛体の配置。姿勢はベクトル部とスカラー部に分けて持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 倍精度の剛体の配置 {
    重心の位置: 倍精度の三次元ベクトル,
    姿勢のベクトル部: 倍精度の三次元ベクトル,
    姿勢のスカラー部: f64,
}

impl 倍精度の剛体の配置 {
    /// 単精度の配置を倍精度へ広げる。値は1ビットも変わらず、以後の演算だけが倍精度になる。
    pub(in crate::contact) fn 単精度の配置から広げる(単精度: &配置) -> Self {
        let [x, y, z, w] = 単精度.姿勢().境界用xyzw配列();
        Self {
            重心の位置: 倍精度の三次元ベクトル::単精度の位置から広げる(単精度.重心の位置()),
            姿勢のベクトル部: 倍精度の三次元ベクトル::成分から生成する(f64::from(x), f64::from(y), f64::from(z)),
            姿勢のスカラー部: f64::from(w),
        }
    }

    pub(in crate::contact) fn 重心の位置(&self) -> 倍精度の三次元ベクトル {
        self.重心の位置
    }

    /// 重心局所の点を世界の腕 R(q) r̄ へ写す。
    pub(in crate::contact) fn 腕(&self, 局所点: &倍精度の三次元ベクトル) -> 倍精度の三次元ベクトル {
        self.姿勢で回す(局所点)
    }

    /// 重心局所の点の世界位置 x + R(q) r̄。
    pub(in crate::contact) fn 局所点の世界位置(&self, 局所点: &倍精度の三次元ベクトル) -> 倍精度の三次元ベクトル {
        self.重心の位置.足す(&self.腕(局所点))
    }

    /// この配置の姿勢で回したベクトル v + 2w(u × v) + 2u × (u × v)。u は姿勢のベクトル部である。
    pub(in crate::contact) fn 姿勢で回す(&self, ベクトル: &倍精度の三次元ベクトル) -> 倍精度の三次元ベクトル {
        姿勢の成分で回す(&self.姿勢のベクトル部, self.姿勢のスカラー部, ベクトル)
    }
}

/// 単位四元数の成分でベクトルを回す。2つの回転(剛体の姿勢と主軸)に対して対等な計算であるためレシーバを持たない。
pub(in crate::contact) fn 姿勢の成分で回す(
    ベクトル部: &倍精度の三次元ベクトル,
    スカラー部: f64,
    ベクトル: &倍精度の三次元ベクトル,
) -> 倍精度の三次元ベクトル {
    let 一度目の外積 = ベクトル部.外積(ベクトル);
    let 二度目の外積 = ベクトル部.外積(&一度目の外積);
    ベクトル
        .足す(&一度目の外積.比で伸ばす(2.0 * スカラー部))
        .足す(&二度目の外積.比で伸ばす(2.0))
}

/// 単精度の四元数を倍精度のベクトル部とスカラー部へ広げる。主軸の回転を読む側が使う。
pub(in crate::contact) fn 単精度の四元数から広げる<入力空間: 空間, 出力空間: 空間>(
    単精度: &クォータニオン<入力空間, 出力空間>,
) -> (倍精度の三次元ベクトル, f64) {
    let [x, y, z, w] = 単精度.境界用xyzw配列();
    (
        倍精度の三次元ベクトル::成分から生成する(f64::from(x), f64::from(y), f64::from(z)),
        f64::from(w),
    )
}
