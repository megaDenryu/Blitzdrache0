//! 倍精度の剛体の配置(Issue #59の数値契約の診断)。重心の世界位置と姿勢を持ち、重心局所の点を世界へ写す。
//! 単精度の`配置`が`glam`で行う写しと同じ式を倍精度で書き直したものである。
//! 姿勢そのもの(`orientation`)から分けているのは、こちらが「どこに居るか」を持ち、あちらが「どちらを向いて
//! いるか」だけを持つからである。回す操作は姿勢の側にあり、この型は重心の位置を足す責任だけを持つ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断9: 拘束の勾配から並進と回転の補正を一般化逆質量で分配し、確定後に速度と角速度を再構成する」

#![cfg(test)]

use super::orientation::倍精度の姿勢;
use super::vector::倍精度の三次元ベクトル;
use crate::rigid_body::{姿勢, 配置};

/// 倍精度の剛体の配置。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 倍精度の剛体の配置 {
    重心の位置: 倍精度の三次元ベクトル,
    姿勢: 倍精度の姿勢,
}

impl 倍精度の剛体の配置 {
    /// 単精度の配置を倍精度へ広げる。値は1ビットも変わらず、以後の演算だけが倍精度になる。
    pub(in crate::contact) fn 単精度の配置から広げる(単精度: &配置) -> Self {
        Self {
            重心の位置: 倍精度の三次元ベクトル::単精度の位置から広げる(単精度.重心の位置()),
            姿勢: 倍精度の姿勢::単精度の姿勢から広げる(単精度.姿勢()),
        }
    }

    /// 世界の原点に置いた恒等の姿勢の配置。動かせない参加者は配置を読まれないため、この値で足りる。
    pub(in crate::contact) fn 原点に置いた恒等の姿勢で生成する() -> Self {
        Self {
            重心の位置: 倍精度の三次元ベクトル::零(),
            姿勢: 倍精度の姿勢::単精度の姿勢から広げる(&姿勢::恒等()),
        }
    }

    pub(in crate::contact) fn 姿勢(&self) -> 倍精度の姿勢 {
        self.姿勢
    }

    /// 重心局所の点を世界の腕 R(q) r̄ へ写す。
    pub(in crate::contact) fn 腕(&self, 局所点: &倍精度の三次元ベクトル) -> 倍精度の三次元ベクトル {
        self.姿勢.回す(局所点)
    }

    /// 重心局所の点の世界位置 x + R(q) r̄。
    pub(in crate::contact) fn 局所点の世界位置(&self, 局所点: &倍精度の三次元ベクトル) -> 倍精度の三次元ベクトル {
        self.重心の位置.足す(&self.腕(局所点))
    }
}
