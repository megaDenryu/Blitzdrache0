//! 参照計算が行の右辺を解けたと見なす許容差をどこから採るかの選択(Issue #59の数値契約の診断)。
//! 枝は2つである。倍精度の座標の表現の刻みから導く枝と、単精度の行が持つ許容差をそのまま据え置く枝である。
//! 2つを持つのは、単精度と倍精度の差がどこから来るかを分けるためである。倍精度の刻みから導く枝は
//! 「座標をいくらでも細かく表せるなら解法が何を返すか」を答え、単精度の許容差を据え置く枝は
//! 「許容差の取り決めを変えずに演算だけ倍精度にしたら何が変わるか」を答える。
//! 前者と単精度の差には許容差の効果と演算の丸めの両方が混ざるが、後者と単精度の差には演算の丸めしか残らない。
//! 2つの差を並べれば、どちらの寄与が大きいかが引き算で読める。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

/// 参照計算が行の許容差をどこから採るか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(in crate::contact) enum 参照計算の許容差の由来 {
    /// 倍精度の座標の表現の刻みから導く。許容差はほぼ零になる。
    倍精度の表現の刻みから導く,
    /// 単精度の行が持つ許容差をそのまま据え置く。演算だけが倍精度になる。
    単精度の許容差を据え置く,
}

impl 参照計算の許容差の由来 {
    /// この由来が行へ与える許容差。2つの候補を受け取って枝で選ぶ。
    pub(in crate::contact) fn 行の許容差を選ぶ(&self, 倍精度の刻みから: f64, 単精度の許容差: f64) -> f64 {
        match self {
            Self::倍精度の表現の刻みから導く => 倍精度の刻みから,
            Self::単精度の許容差を据え置く => 単精度の許容差,
        }
    }

    /// 表へ書く由来の綴り。
    pub(in crate::contact) fn 綴り(&self) -> &'static str {
        match self {
            Self::倍精度の表現の刻みから導く => "倍精度の刻み",
            Self::単精度の許容差を据え置く => "単精度の許容差",
        }
    }
}
