//! 倍精度のワールドの逆慣性(Issue #59の数値契約の診断)。3×3の行列を持たず、主軸の世界の向き3本と逆主慣性
//! 3つで持つ。I⁻¹ = Σ_k J_k⁻¹ a_k a_kᵀ であり、この形なら行列の型を作らずに I⁻¹ v = Σ_k J_k⁻¹ (a_k·v) a_k で
//! 作用させられるためである。単精度の`逆慣性テンソル`が主軸と逆主慣性から組む式と同じものである。
//! 動かせない参加者は逆主慣性を全部零にして表す。単精度の側が零のテンソルで表すのと同じ意味である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断4: 質量特性は質量・物体原点から見た重心・主慣性と主軸で持ち、生成で物理的な有効性を検証する」

#![cfg(test)]

use super::orientation::倍精度の姿勢;
use super::vector::倍精度の三次元ベクトル;
use crate::rigid_body::質量特性;

/// 倍精度のワールドの逆慣性。主軸の世界の向きと、その軸まわりの逆主慣性の組を3つ持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 倍精度のワールドの逆慣性 {
    主軸の世界の向き: [倍精度の三次元ベクトル; 3],
    逆主慣性: [f64; 3],
}

impl 倍精度のワールドの逆慣性 {
    /// 質量特性の主軸と逆主慣性を、渡した姿勢で世界へ回して組む。
    pub(in crate::contact) fn 質量特性と姿勢から組む(質量特性: &質量特性, 剛体の姿勢: 倍精度の姿勢) -> Self {
        let 主慣性と主軸 = 質量特性.主慣性と主軸();
        let 主軸の姿勢 = 倍精度の姿勢::単精度の四元数から広げる(主慣性と主軸.主軸());
        let 逆主慣性の単精度 = 主慣性と主軸.逆主慣性();
        let mut 主軸の世界の向き = [倍精度の三次元ベクトル::零(); 3];
        let mut 逆主慣性 = [0.0; 3];
        for (番号, 一本) in 主軸の世界の向き.iter_mut().enumerate() {
            *一本 = 剛体の姿勢.回す(&主軸の姿勢.回す(&第k番の基底(番号)));
            逆主慣性[番号] = f64::from(逆主慣性の単精度[番号].値());
        }
        Self {
            主軸の世界の向き, 逆主慣性
        }
    }

    /// 動かせない参加者の実効の重み。逆主慣性を全部零にする。
    pub(in crate::contact) fn 零() -> Self {
        Self {
            主軸の世界の向き: [倍精度の三次元ベクトル::零(); 3],
            逆主慣性: [0.0; 3],
        }
    }

    /// ベクトルへ作用させた I⁻¹ v = Σ_k J_k⁻¹ (a_k·v) a_k。
    pub(in crate::contact) fn ベクトルへ作用させる(
        &self, ベクトル: &倍精度の三次元ベクトル
    ) -> 倍精度の三次元ベクトル {
        let mut 合計 = 倍精度の三次元ベクトル::零();
        for (軸, 逆慣性) in self.主軸の世界の向き.iter().zip(self.逆主慣性.iter()) {
            合計 = 合計.足す(&軸.比で伸ばす(逆慣性 * 軸.内積(ベクトル)));
        }
        合計
    }
}

// 第k番の座標軸の単位ベクトル。前提: 番号は3より小さい(主軸は3本である)。
fn 第k番の基底(番号: usize) -> 倍精度の三次元ベクトル {
    match 番号 {
        0 => 倍精度の三次元ベクトル::成分から生成する(1.0, 0.0, 0.0),
        1 => 倍精度の三次元ベクトル::成分から生成する(0.0, 1.0, 0.0),
        2 => 倍精度の三次元ベクトル::成分から生成する(0.0, 0.0, 1.0),
        _ => panic!("主軸は3本であるはずの不変条件の破れ: 軸の番号{番号}"),
    }
}
