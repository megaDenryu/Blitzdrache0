//! 倍精度の参照計算で、抜き出した連立の何番目の行がどの接触点のどちらの拘束かを持つ並び(Issue #59の診断)。
//! 単精度の`抜き出した行の並び`と同じ順(法線の行を番号の昇順、その後ろへ接線の行を番号の昇順)である。
//! 順を単精度と揃えるのは、行ごとの残差と捨てた向きを2つの経路で番号どうし突き合わせるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_collision::contact_set::接触点の上限;

use super::active_set::倍精度の連立の有効集合;
use super::gradient::倍精度の一行の二つの符号付き勾配;
use super::manifold_system::倍精度の接触点集合の連立;

/// 抜き出した連立の1行が、どの接触点のどちらの拘束から来たか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(in crate::contact) enum 倍精度の抜き出した行の持ち主 {
    /// その接触点の法線の隔たりを動かさない行である。
    法線の行を持つ点(usize),
    /// その接触点の錨の接線変位を零へ戻す行である。
    接線の行を持つ点(usize),
}

impl 倍精度の抜き出した行の持ち主 {
    /// この行の勾配。行を持たない点を指していれば無しである。
    pub(in crate::contact) fn 行の勾配(
        &self, 連立: &倍精度の接触点集合の連立
    ) -> Option<倍精度の一行の二つの符号付き勾配> {
        match self {
            Self::法線の行を持つ点(番号) => 連立.法線の一行を読む(*番号).map(|一行| *一行.勾配()),
            Self::接線の行を持つ点(番号) => 連立.接線の一行を読む(*番号).map(|一行| *一行.勾配()),
        }
    }

    /// この行の連立の右辺。行を持たない点を指していれば零である。
    pub(in crate::contact) fn 行の右辺(&self, 連立: &倍精度の接触点集合の連立) -> f64 {
        match self {
            Self::法線の行を持つ点(番号) => 連立.法線の一行を読む(*番号).map_or(0.0, |一行| 一行.連立の右辺()),
            Self::接線の行を持つ点(番号) => 連立.接線の一行を読む(*番号).map_or(0.0, |一行| 一行.連立の右辺()),
        }
    }

    /// この行の対角へ足すコンプライアンスの刻み依存量 α̃。接線の行は硬い位置拘束であるため零である。
    pub(in crate::contact) fn 行の対角へ足す刻み依存量(&self, 連立: &倍精度の接触点集合の連立) -> f64 {
        match self {
            Self::法線の行を持つ点(番号) => 連立.法線の一行を読む(*番号).map_or(0.0, |一行| 一行.刻み依存量()),
            Self::接線の行を持つ点(_) => 0.0,
        }
    }
}

/// 有効集合に絞った行の並び。
pub(in crate::contact) struct 倍精度の抜き出した行の並び {
    法線の行のもとの点の番号: [usize; 接触点の上限],
    法線の行の数: usize,
    接線の行のもとの点の番号: [usize; 接触点の上限],
    接線の行の数: usize,
}

impl 倍精度の抜き出した行の並び {
    pub(in crate::contact) fn 有効集合から組む(
        連立: &倍精度の接触点集合の連立, 有効集合: &倍精度の連立の有効集合
    ) -> Self {
        let mut 並び = Self {
            法線の行のもとの点の番号: [0; 接触点の上限],
            法線の行の数: 0,
            接線の行のもとの点の番号: [0; 接触点の上限],
            接線の行の数: 0,
        };
        for 点の番号 in (0..連立.点の数()).filter(|番号| 有効集合.有効か(*番号)) {
            if 連立.法線の一行を読む(点の番号).is_some() {
                並び.法線の行のもとの点の番号[並び.法線の行の数] = 点の番号;
                並び.法線の行の数 += 1;
            }
            if 連立.接線の一行を読む(点の番号).is_some() {
                並び.接線の行のもとの点の番号[並び.接線の行の数] = 点の番号;
                並び.接線の行の数 += 1;
            }
        }
        並び
    }

    pub(in crate::contact) fn 行の数(&self) -> usize {
        self.法線の行の数 + self.接線の行の数
    }

    pub(in crate::contact) fn 法線の行の数(&self) -> usize {
        self.法線の行の数
    }

    pub(in crate::contact) fn 接線の行の数(&self) -> usize {
        self.接線の行の数
    }

    pub(in crate::contact) fn 法線の行のもとの点の番号(&self, 法線の行の番号: usize) -> usize {
        self.法線の行のもとの点の番号[法線の行の番号]
    }

    pub(in crate::contact) fn 接線の行のもとの点の番号(&self, 接線の行の番号: usize) -> usize {
        self.接線の行のもとの点の番号[接線の行の番号]
    }

    /// 抜き出した連立の第k行の持ち主。前提: k は行の数より小さい。
    pub(in crate::contact) fn 第k行の持ち主(&self, k: usize) -> 倍精度の抜き出した行の持ち主 {
        if k < self.法線の行の数 {
            倍精度の抜き出した行の持ち主::法線の行を持つ点(self.法線の行のもとの点の番号[k])
        } else {
            倍精度の抜き出した行の持ち主::接線の行を持つ点(self.接線の行のもとの点の番号[k - self.法線の行の数])
        }
    }
}
