//! 倍精度の、抜き出した連立を解いた行の残差と補正の大きさを測る工程(Issue #59の数値契約の診断)。
//! 単精度の`reduced_system_residual`と同じ2つの量を同じ式で測る。許容差の内側かを見るのは残差の全体ではなく、
//! 許容差の内側として捨てた右辺の成分だけである。残差にはこの連立の階数では満たせない成分も混ざり、そちらは
//! 座標を倍精度にしても消えない。参照計算がその2つを分けて持つことが、Issue #59が求める
//! 「アルゴリズムの不足と表現精度の不足の区別」そのものである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::super::super::symmetric_system::法線と接線の連立の行の上限;
use super::pseudo_inverse::倍精度の擬似逆で解いた増分と捨てた右辺;
use super::reduced_system::倍精度の抜き出した連立;

/// 倍精度の、1つの有効集合で解いた結果の質。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 倍精度の解いた行の残差と補正の大きさ {
    残差のノルム: f64,
    補正の質量の計量のノルム: f64,
    全部の行の残差が許容差の内側か: bool,
}

impl 倍精度の解いた行の残差と補正の大きさ {
    /// 全部の行の残差が、その行を解けたと見なす許容差の内側に収まったか。
    pub(in crate::contact) fn 全部の行の残差が許容差の内側か(&self) -> bool {
        self.全部の行の残差が許容差の内側か
    }

    /// 残差のノルム ‖A Δλ − b‖。診断の表が単精度の側と並べて綴る量である。
    pub(in crate::contact) fn 残差のノルム(&self) -> f64 {
        self.残差のノルム
    }

    /// 残差のノルムを先に、同じなら補正の質量の計量のノルムを比べる順序。どちらも小さい方を先に選ぶ。
    pub(in crate::contact) fn 先に選ぶ順で比べる(&self, 相手: &Self) -> std::cmp::Ordering {
        self.残差のノルム
            .total_cmp(&相手.残差のノルム)
            .then_with(|| self.補正の質量の計量のノルム.total_cmp(&相手.補正の質量の計量のノルム))
    }
}

impl 倍精度の抜き出した連立 {
    /// 解いた増分の残差 (A Δλ)_k − b_k と、補正の質量の計量のノルム √(Δλᵀ A Δλ) を測る。
    pub(in crate::contact) fn 解いた行の残差と補正の大きさを測る(
        &self,
        解: &倍精度の擬似逆で解いた増分と捨てた右辺,
    ) -> 倍精度の解いた行の残差と補正の大きさ {
        let 増分 = 解.増分();
        let mut 残差の二乗和 = 0.0;
        let mut 補正の二乗 = 0.0;
        let mut 全部の行が許容差の内側 = true;
        for k in 0..self.並び.行の数() {
            let 積 = self.第k行と解の積(増分, k);
            let 残差 = 積 - self.定数項[k];
            残差の二乗和 += 残差 * 残差;
            補正の二乗 += 増分[k] * 積;
            全部の行が許容差の内側 &= 解.第k行の許容差の内側として捨てた右辺(k).abs() <= self.行ごとの解けたと見なす許容差[k];
        }
        倍精度の解いた行の残差と補正の大きさ {
            残差のノルム: 残差の二乗和.sqrt(),
            補正の質量の計量のノルム: 補正の二乗.max(0.0).sqrt(),
            全部の行の残差が許容差の内側か: 全部の行が許容差の内側,
        }
    }

    /// 第k行の残差 (A Δλ)_k − b_k。診断の表が行ごとに綴る量である。
    pub(in crate::contact) fn 第k行の残差(&self, 解: &倍精度の擬似逆で解いた増分と捨てた右辺, k: usize) -> f64 {
        self.第k行と解の積(解.増分(), k) - self.定数項[k]
    }

    // 第k行と解の積 (A Δλ)_k。
    fn 第k行と解の積(&self, 解: &[f64; 法線と接線の連立の行の上限], k: usize) -> f64 {
        self.対称行列[k]
            .iter()
            .zip(解.iter())
            .take(self.並び.行の数())
            .map(|(成分, 増分)| 成分 * 増分)
            .sum()
    }
}
