//! 倍精度の姿勢(Issue #59の数値契約の診断)。単位四元数のベクトル部とスカラー部を持ち、ベクトルを回す。
//! ベクトル部とスカラー部を別々の値として持ち回らずこの型に包むのは、2つが常に揃って渡され、片方だけが別の
//! 四元数のものになる組み合わせが有り得ないためである。
//! 回転の式に四元数の積を使わず「v + 2w(u × v) + 2u × (u × v)」を直に書くのは、四元数の積の型と綴りを増やさずに
//! 同じ回転が得られるためである。単精度から広げる口が2つあるのは、剛体の姿勢が`姿勢`で、慣性の主軸が
//! `クォータニオン`で表されており、どちらも同じ倍精度の姿勢へ写るためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断3: 配置は重心の世界位置と単位四元数の姿勢であり、正規化は姿勢の型が守る」

#![cfg(test)]

use blitz_math::{クォータニオン, 空間};

use super::vector::倍精度の三次元ベクトル;
use crate::rigid_body::姿勢;

/// 倍精度の単位四元数の姿勢。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 倍精度の姿勢 {
    ベクトル部: 倍精度の三次元ベクトル,
    スカラー部: f64,
}

impl 倍精度の姿勢 {
    /// 剛体の姿勢を倍精度へ広げる。値は1ビットも変わらず、以後の演算だけが倍精度になる。
    pub(in crate::contact) fn 単精度の姿勢から広げる(単精度: &姿勢) -> Self {
        Self::xyzw配列から組む(単精度.境界用xyzw配列())
    }

    /// 慣性の主軸の回転を倍精度へ広げる。主軸座標から重心局所座標への回転である。
    pub(in crate::contact) fn 単精度の四元数から広げる<入力空間: 空間, 出力空間: 空間>(
        単精度: &クォータニオン<入力空間, 出力空間>,
    ) -> Self {
        Self::xyzw配列から組む(単精度.境界用xyzw配列())
    }

    /// この姿勢で回したベクトル v + 2w(u × v) + 2u × (u × v)。u はベクトル部である。
    pub(in crate::contact) fn 回す(&self, ベクトル: &倍精度の三次元ベクトル) -> 倍精度の三次元ベクトル {
        let 一度目の外積 = self.ベクトル部.外積(ベクトル);
        let 二度目の外積 = self.ベクトル部.外積(&一度目の外積);
        ベクトル
            .足す(&一度目の外積.比で伸ばす(2.0 * self.スカラー部))
            .足す(&二度目の外積.比で伸ばす(2.0))
    }

    fn xyzw配列から組む(xyzw: [f32; 4]) -> Self {
        let [x, y, z, w] = xyzw;
        Self {
            ベクトル部: 倍精度の三次元ベクトル::成分から生成する(f64::from(x), f64::from(y), f64::from(z)),
            スカラー部: f64::from(w),
        }
    }
}
