//! 単精度の法線の行から広げて受け取る4つの量(Issue #59の数値契約の診断)。
//! 参照計算が自分で組み直さずに単精度の値を広げるのは、どれも「行の組み立て以降の演算の精度」ではなく、
//! 時間の側の予算と表現の側の事実だからである。
//! 法線のラグランジュ乗数はその細分でそこまでに積んだ値、乗数の上限は1細分で詰めてよい貫通の長さから来る予算、
//! 刻み依存量はコンプライアンスと刻み幅から来る係数である。
//! **隔たりの表現の刻みを倍精度で組み直してはならない。** これは「配置が1ビットも動かない」という表現の事実で
//! あり、参照計算が解いた補正を実際に適用する先は単精度の配置である。倍精度の刻み(1e-15の桁)を使うと、
//! 相補条件の「有効でない点が補正の後も刻みを超えて食い込むか」の判定が実質の零許容になり、どの部分集合も
//! 条件を満たさなくなる(実測で、単精度が定まる細分に対して参照計算が「相補条件を満たす有効集合が無い」を返した)。
//! 行の右辺を解けたと見なす許容差はこれと別であり、あちらは取り決めであるため倍精度で細かくしてよい。
//! この2つを分けることが、Issue #59が求める「物理契約と数値契約の分離」そのものである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

#![cfg(test)]

use super::super::super::non_penetration::非貫通の接触点集合の一行;

/// 単精度の法線の行から広げた、時間の側の予算と表現の側の事実。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 単精度の法線の行から広げた量 {
    pub(in crate::contact) 法線のラグランジュ乗数: f64,
    pub(in crate::contact) 乗数の上限: f64,
    pub(in crate::contact) 刻み依存量: f64,
    pub(in crate::contact) 隔たりの表現の刻み: f64,
}

impl 単精度の法線の行から広げた量 {
    pub(in crate::contact) fn 単精度の行から広げる(単精度の行: &非貫通の接触点集合の一行) -> Self {
        Self {
            法線のラグランジュ乗数: f64::from(単精度の行.法線のラグランジュ乗数().値()),
            乗数の上限: f64::from(単精度の行.乗数の上限().値()),
            刻み依存量: f64::from(単精度の行.刻み依存量().値()),
            隔たりの表現の刻み: f64::from(単精度の行.隔たりの表現の刻み().値()),
        }
    }
}
