//! 単精度の接触点集合から倍精度の連立を組む工程(Issue #59の数値契約の診断)。単精度の細分の工程が進めた配置・
//! 錨・接触点集合・法線の乗数をそのまま入力にして、行の組み立てから先だけを倍精度で行う。
//! 入力を単精度から受け取るのは、参照計算が答えるべき問いが「同じ配置に対して解法が何を返すか」だからである。
//! 軌道そのものを倍精度で回すと配置が単精度の経路と離れ、比べた差がどの環から来たか分からなくなる。
//! この境界により、この参照計算が測るのは「行の組み立て以降の演算の精度と許容差の取り決め」であり、配置の座標
//! そのものの量子化は測らない。座標の量子化は世界内の平行移動の診断が別に測る。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::manifold_system::倍精度の接触点集合の連立;
use super::normal_row::倍精度の法線の一行;
use super::participant::倍精度の姿勢自由度の参加者;
use super::participant_point::倍精度の接触の射影に参加する点;
use super::tangential_row::倍精度の接線の一行;
use super::vector::倍精度の三次元ベクトル;
use crate::rigid_body::{質量特性, 配置};
use crate::rigid_xpbd::姿勢自由度の参加者;

impl 倍精度の接触点集合の連立 {
    /// 単精度の接触点集合と、その反復の予測の配置から倍精度の連立を組む。
    /// 積む行の有無の判断(接線変位が零の点・滑走中の点・両方が動かせない点を入れない)は単精度の側と同じである。
    pub(in crate::contact) fn 単精度の接触点集合から広げる(
        接触点集合: &[剛体と静的世界の接触拘束],
        配置: &配置,
        質量特性: &質量特性,
    ) -> Self {
        let 単精度の参加者 = 姿勢自由度の参加者::動的(*配置, 質量特性);
        let 参加者 = 倍精度の姿勢自由度の参加者::単精度の配置と質量特性から広げる(配置, 質量特性);
        let mut 連立 = Self::点の数から空で始める(接触点集合.len());
        for (点の番号, 拘束) in 接触点集合.iter().enumerate() {
            連立.法線の一行を積む(点の番号, 法線の一行を広げる(拘束, &単精度の参加者, 参加者));
            if let Some(接線の一行) = 接線の一行を広げる(拘束, 参加者) {
                連立.接線の一行を積む(点の番号, 接線の一行);
            }
        }
        連立
    }
}

// 接触点1つの法線の行を倍精度で組む。乗数の上限と刻み依存量は時間の側の予算であるため単精度の行から広げる。
fn 法線の一行を広げる(
    拘束: &剛体と静的世界の接触拘束,
    単精度の参加者: &姿勢自由度の参加者,
    参加者: 倍精度の姿勢自由度の参加者,
) -> 倍精度の法線の一行 {
    let 単精度の行 = 拘束.同時解法の一行にする(単精度の参加者);
    倍精度の法線の一行::参加点と法線から生成する(
        倍精度の接触の射影に参加する点::剛体の局所点から生成する(参加者, 拘束.引数().剛体側の局所接触点),
        倍精度の接触の射影に参加する点::静的世界の固定点から生成する(拘束.引数().静的世界側の接触点),
        倍精度の三次元ベクトル::単精度の方向から広げる(拘束.引数().接触法線),
        f64::from(拘束.法線のラグランジュ乗数().値()),
        f64::from(単精度の行.乗数の上限().値()),
        f64::from(単精度の行.刻み依存量().値()),
    )
}

// 接触点1つの接線の行を倍精度で組む。既に滑走中の点は単精度の側と同じく行を持たない。
fn 接線の一行を広げる(
    拘束: &剛体と静的世界の接触拘束, 参加者: 倍精度の姿勢自由度の参加者
) -> Option<倍精度の接線の一行> {
    if 拘束.静止摩擦の解の状態().滑走中か() {
        return None;
    }
    let 錨 = 拘束.静止摩擦の錨();
    倍精度の接線の一行::二つの錨と接触法線から生成する(
        倍精度の接触の射影に参加する点::剛体の局所点から生成する(参加者, 錨.第1の参加者の重心局所点()),
        倍精度の接触の射影に参加する点::静的世界の固定点から生成する(錨.第2の参加者から見た点()),
        &倍精度の三次元ベクトル::単精度の方向から広げる(拘束.引数().接触法線),
    )
}
