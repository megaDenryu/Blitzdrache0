//! 倍精度の対称な連立のヤコビ法による固有分解(Issue #59の数値契約の診断)。単精度の`対称な連立の固有分解`と
//! 同じ掃きの順・同じ回数で回す。違うのは演算の精度と、回さない非対角の大きさの下限だけである。
//! 下限を単精度の1e-12より小さく置くのは、倍精度の行列では1e-12が既に意味のある非対角の成分だからである。
//! 単精度の下限をそのまま使うと、参照計算の側が本物の非対角を残したまま「対角化した」と見なすことになる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::super::super::symmetric_system::法線と接線の連立の行の上限;

// 掃きの回数。単精度の側と同じである。
const 掃きの回数: usize = 12;

// 非対角の成分をこれ以下と見なして回さない大きさ。倍精度の行列の規模に合わせて単精度の下限より小さく置く。
const 回さない非対角の大きさ: f64 = 1.0e-30;

/// 倍精度の対称な連立の固有分解。固有値と、その固有ベクトルを列に持つ行列である。
pub(in crate::contact) struct 倍精度の対称な連立の固有分解 {
    pub(super) 固有値: [f64; 法線と接線の連立の行の上限],
    pub(super) 固有ベクトルの列: [[f64; 法線と接線の連立の行の上限]; 法線と接線の連立の行の上限],
    pub(super) 個数: usize,
}

impl 倍精度の対称な連立の固有分解 {
    /// ヤコビ法で分解する。対称であることは呼び出し側が組み立てで保証する。
    pub(in crate::contact) fn 分解する(
        対称行列: &[[f64; 法線と接線の連立の行の上限]; 法線と接線の連立の行の上限], 個数: usize
    ) -> Self {
        let mut 分解 = Self {
            固有値: [0.0; 法線と接線の連立の行の上限],
            固有ベクトルの列: [[0.0; 法線と接線の連立の行の上限]; 法線と接線の連立の行の上限],
            個数,
        };
        let mut 対角へ寄せる行列 = *対称行列;
        for (k, 第k行) in 分解.固有ベクトルの列.iter_mut().enumerate().take(個数) {
            第k行[k] = 1.0;
        }
        for _ in 0..掃きの回数 {
            for p in 0..個数 {
                for q in (p + 1)..個数 {
                    分解.一つの非対角を消す(&mut 対角へ寄せる行列, p, q);
                }
            }
        }
        for (k, 固有値) in 分解.固有値.iter_mut().enumerate().take(個数) {
            *固有値 = 対角へ寄せる行列[k][k];
        }
        分解
    }

    /// 第k番の固有値。診断の表が固有値の散らばりを綴るために読む。
    pub(in crate::contact) fn 第k番の固有値(&self, k: usize) -> f64 {
        self.固有値[k]
    }

    /// 第k番の固有ベクトルの第i成分。診断の表が右辺の射影を求めるために読む。
    pub(in crate::contact) fn 第k番の固有ベクトルの成分(&self, k: usize, i: usize) -> f64 {
        self.固有ベクトルの列[i][k]
    }

    // 第p行第q列の非対角の成分を消すヤコビ回転。行列と固有ベクトルの列の両方を同じ角で回す。
    fn 一つの非対角を消す(
        &mut self, 行列: &mut [[f64; 法線と接線の連立の行の上限]; 法線と接線の連立の行の上限], p: usize, q: usize
    ) {
        if 行列[p][q].abs() < 回さない非対角の大きさ {
            return;
        }
        let 傾き = (行列[q][q] - 行列[p][p]) / (2.0 * 行列[p][q]);
        let 正接 = 傾き.signum() / (傾き.abs() + (傾き * 傾き + 1.0).sqrt());
        let 余弦 = 1.0 / (正接 * 正接 + 1.0).sqrt();
        let 正弦 = 正接 * 余弦;
        let 個数 = self.個数;
        for 第k行 in 行列.iter_mut().take(個数) {
            let (左, 右) = (第k行[p], 第k行[q]);
            第k行[p] = 余弦 * 左 - 正弦 * 右;
            第k行[q] = 正弦 * 左 + 余弦 * 右;
        }
        let (第p行, 第q行) = (行列[p], 行列[q]);
        for (k, (左, 右)) in 第p行.iter().zip(第q行.iter()).enumerate().take(個数) {
            行列[p][k] = 余弦 * 左 - 正弦 * 右;
            行列[q][k] = 正弦 * 左 + 余弦 * 右;
        }
        for 第k行 in self.固有ベクトルの列.iter_mut().take(個数) {
            let (左, 右) = (第k行[p], 第k行[q]);
            第k行[p] = 余弦 * 左 - 正弦 * 右;
            第k行[q] = 正弦 * 左 + 余弦 * 右;
        }
    }
}
