//! 単精度と倍精度の乗数の増分と円錐の判定が一致することの試験(Issue #59)。
//! 乗数は長さを有効逆質量で割った量であり、一般化逆質量の外積と内積、擬似逆の固有分解という演算の丸めが乗る。
//! したがって行の許容差でなく相対の差で比べる。許容差の取り決めは両方の経路で同じ値に揃えてあるため、残る差は
//! 演算の丸めだけである。
//! 拘束違反の一致は`constraint_violation_tests`が固定する。分けているのは、あちらが行の右辺の材料になる長さを
//! 見るのに対し、こちらが連立を解いた後の値を見るからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::cone_judgement::倍精度の円錐の判定;
use super::double_reference_fixture::{
    単精度の連立を組む, 許容差を据え置いて倍精度で解く, 錨をずらした接触点一つを組む
};

// 乗数の増分の差を、その量そのものの大きさで割った比の上限。演算の丸めが乗る量である。
const 乗数が一致と見なす相対の差: f64 = 1.0e-5;

#[test]
fn 接触点一つでは単精度と倍精度の乗数の増分と円錐の判定が一致する() {
    let (拘束, 配置) = 錨をずらした接触点一つを組む();
    let 単精度の解 = 単精度の連立を組む(&拘束, &配置)
        .相補条件を満たす有効集合で同時に解く()
        .定まった解を取り出す();
    let 参照の解 = 許容差を据え置いて倍精度で解く(拘束, &配置);
    for (名前, 単精度, 倍精度) in [
        (
            "法線の乗数の増分",
            f64::from(単精度の解.一点の法線の乗数の増分(0).値()),
            参照の解.同時解.一点の法線の乗数の増分(0),
        ),
        (
            "接線の乗数の増分",
            f64::from(単精度の解.一点の接線の乗数の増分(0).値()),
            参照の解.同時解.一点の接線の乗数の増分(0),
        ),
    ] {
        let 分母 = 倍精度.abs().max(単精度.abs());
        let 差 = if 分母 > 0.0 { (単精度 - 倍精度).abs() / 分母 } else { 0.0 };
        assert!(差 <= 乗数が一致と見なす相対の差, "{名前}が単精度{単精度}と倍精度{倍精度}で相対{差}離れた");
    }
    assert_eq!(
        単精度の解.一点の法線の行が有効か(0),
        参照の解.同時解.一点の法線の行が有効か(0),
        "法線の有効集合が2つの経路で違う"
    );
    let 判定 = 倍精度の円錐の判定::参照の解と単精度の接触点集合から集計する(&参照の解, &[拘束]);
    assert!(判定.法線の乗数の合計() > 0.0, "参照計算の法線の乗数の合計が正でない");
    assert!(判定.合力と法線の合計の比() > 0.0, "参照計算の接線の合力と法線の合計の比が正でない");
}
