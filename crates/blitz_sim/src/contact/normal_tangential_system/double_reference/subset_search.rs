//! 倍精度の、相補条件を満たす有効集合を全部の部分集合から探す工程と、その結末(Issue #59の数値契約の診断)。
//! 単精度の`subset_search`・`candidate`・`solve_outcome`の3つを同じ決着の順で倍精度に写したものである。
//! 決着の順は4段(有効な点の数が多い方・残差・補正の質量の計量のノルム・ビット並び)であり、単精度の側と同じである。
//! 順を揃えるのは、2つの経路が別の候補を選んだときに「選び方が違う」ではなく「数値が違う」と読めるようにするためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use std::cmp::Ordering;

use super::active_set::倍精度の連立の有効集合;
use super::manifold_system::倍精度の接触点集合の連立;
use super::reduced_system::倍精度の抜き出した連立;
use super::residual::倍精度の解いた行の残差と補正の大きさ;
use super::solution::倍精度の接触点集合の同時解;

/// 倍精度の参照計算が、相補条件を満たす有効集合を探した結末。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) enum 倍精度の有効集合を探した結末 {
    /// 相補条件を満たし、全部の行の残差が許容差の内側に収まる解が定まった。
    有効集合が定まった(倍精度の接触点集合の同時解, 倍精度の連立の有効集合),
    /// どの部分集合も相補条件を満たさなかった。
    相補条件を満たす有効集合が無い,
    /// 相補条件は満たすが、どの候補も行の残差を許容差の内側へ収められなかった。
    表現の精度が不足した,
}

// 相補条件を満たした1つの候補と、決着に使う材料。走査の内側だけで生きる値であるためモジュールに閉じる。
struct 相補条件を満たした候補 {
    同時解: 倍精度の接触点集合の同時解,
    有効集合: 倍精度の連立の有効集合,
    質: 倍精度の解いた行の残差と補正の大きさ,
}

impl 相補条件を満たした候補 {
    // 2つの候補のうち先に選ぶ方。有効な点の数だけは多い方を先に選ぶため、比べる向きを逆にする。
    fn 先に選ぶ方を採る(self, 相手: Self) -> Self {
        let 順 = 相手
            .有効集合
            .ビット並び()
            .count_ones()
            .cmp(&self.有効集合.ビット並び().count_ones())
            .then_with(|| self.質.先に選ぶ順で比べる(&相手.質))
            .then_with(|| self.有効集合.ビット並び().cmp(&相手.有効集合.ビット並び()));
        match 順 {
            Ordering::Greater => 相手,
            Ordering::Less | Ordering::Equal => self,
        }
    }
}

impl 倍精度の接触点集合の連立 {
    /// 取りうる有効集合を全部調べ、相補条件を満たす候補のうち決着の順で先に来る1つを解として返す。
    pub(in crate::contact) fn 相補条件を満たす有効集合で同時に解く(&self) -> 倍精度の有効集合を探した結末 {
        let 候補のビット並び = self.有効集合へ入れてよい点のビット並び();
        let mut 先に選ぶ候補: Option<相補条件を満たした候補> = None;
        let mut ビット並び = 候補のビット並び;
        loop {
            if let Some(候補) = self.一つの部分集合を候補にする(ビット並び) {
                先に選ぶ候補 = Some(match 先に選ぶ候補 {
                    Some(前の候補) => 前の候補.先に選ぶ方を採る(候補),
                    None => 候補,
                });
            }
            if ビット並び == 0 {
                break;
            }
            ビット並び = (ビット並び - 1) & 候補のビット並び;
        }
        match 先に選ぶ候補 {
            None => 倍精度の有効集合を探した結末::相補条件を満たす有効集合が無い,
            Some(候補) if !候補.質.全部の行の残差が許容差の内側か() => {
                倍精度の有効集合を探した結末::表現の精度が不足した
            }
            Some(候補) => 倍精度の有効集合を探した結末::有効集合が定まった(候補.同時解, 候補.有効集合),
        }
    }

    // 1つの部分集合を解き、相補条件を満たすなら候補にする。満たさない集合は無しを返す。
    fn 一つの部分集合を候補にする(&self, ビット並び: u8) -> Option<相補条件を満たした候補> {
        let 有効集合 = 倍精度の連立の有効集合::ビット並びから生成する(ビット並び);
        let 抜き出した = 倍精度の抜き出した連立::抜き出す(self, &有効集合);
        let 解 = 抜き出した.解く();
        let 同時解 = 抜き出した.もとの点へ戻す(&解, self, &有効集合);
        if !self.相補条件を満たすか(&同時解, &有効集合) {
            return None;
        }
        Some(相補条件を満たした候補 {
            質: 抜き出した.解いた行の残差と補正の大きさを測る(&解),
            同時解,
            有効集合,
        })
    }
}
