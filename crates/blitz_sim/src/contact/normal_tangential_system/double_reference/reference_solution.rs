/// 倍精度の参照計算が1つの接触点集合について求めた解。
pub(in crate::contact) struct 倍精度の参照の解 {
    pub(in crate::contact) 連立: 倍精度の接触点集合の連立,
    pub(in crate::contact) 抜き出した: 倍精度の抜き出した連立,
    pub(in crate::contact) 擬似逆の解: 倍精度の擬似逆で解いた増分と捨てた右辺,
    pub(in crate::contact) 同時解: 倍精度の接触点集合の同時解,
    pub(in crate::contact) 有効集合: 倍精度の連立の有効集合,
}

/// 倍精度の参照計算が1つの接触点集合を解いた結末。
pub(in crate::contact) enum 倍精度の参照の結末 {
    /// 有効集合が定まり、解と診断の量が読める。
    解が定まった(倍精度の参照の解),
    /// どの部分集合も相補条件を満たさなかった。
    相補条件を満たす有効集合が無い,
    /// 相補条件は満たすが、どの候補も行の残差を許容差の内側へ収められなかった。
    表現の精度が不足した,
}

impl 倍精度の参照の結末 {
    /// 単精度の接触点集合と、その反復の予測の配置から倍精度で解く。
    pub(in crate::contact) fn 単精度の接触点集合から求める(
        接触点集合: &[剛体と静的世界の接触拘束],
        配置: &配置,
        質量特性: &質量特性,
    ) -> Self {
        let 連立 = 倍精度の接触点集合の連立::単精度の接触点集合から広げる(接触点集合, 配置, 質量特性);
        match 連立.相補条件を満たす有効集合で同時に解く() {
            倍精度の有効集合を探した結末::相補条件を満たす有効集合が無い => {
                Self::相補条件を満たす有効集合が無い
            }
            倍精度の有効集合を探した結末::表現の精度が不足した => Self::表現の精度が不足した,
            倍精度の有効集合を探した結末::有効集合が定まった(同時解, 有効集合) => {
                let 抜き出した = 倍精度の抜き出した連立::抜き出す(&連立, &有効集合);
                let 擬似逆の解 = 抜き出した.解く();
                Self::解が定まった(倍精度の参照の解 {
                    連立,
                    抜き出した,
                    擬似逆の解,
                    同時解,
                    有効集合,
                })
            }
        }
    }

    /// 結末を1語で表す綴り。診断の表が単精度の側の結末と並べて綴る。
    pub(in crate::contact) fn 結末の綴り(&self) -> &'static str {
        match self {
            Self::解が定まった(_) => "定まった",
            Self::相補条件を満たす有効集合が無い => "相補条件を満たす有効集合が無い",
            Self::表現の精度が不足した => "表現の精度が不足した",
        }
    }
}

impl 倍精度の参照の解 {
    /// 点ごとの、更新後の法線の乗数 λ_n + Δλ_n。
    pub(in crate::contact) fn 一点の更新後の法線の乗数(&self, 点の番号: usize) -> f64 {
        let 前 = self.連立.法線の一行を読む(点の番号).map_or(0.0, |一行| 一行.法線のラグランジュ乗数());
        前 + self.同時解.一点の法線の乗数の増分(点の番号)
    }

    /// 更新後の法線の乗数の合計 Σλ_n。円錐の半径を決める値である。
    pub(in crate::contact) fn 更新後の法線の乗数の合計(&self) -> f64 {
        (0..self.連立.点の数()).map(|番号| self.一点の更新後の法線の乗数(番号)).sum()
    }

    /// 点ごとの法線の拘束違反 C_n(いまの配置の隔たり)。行を持たない点は零である。
    pub(in crate::contact) fn 一点の法線の拘束違反(&self, 点の番号: usize) -> f64 {
        self.連立.法線の一行を読む(点の番号).map_or(0.0, |一行| 一行.隔たり())
    }

    /// この点が円錐の判定へ渡す仮の接線の乗数。単精度の`接触点の仮の接線の乗数`と同じ場合分けである。
    /// 法線の行が有効集合から外れた点は零へ解放し、接線の行を積んだ点は λ_t + Δs t を渡し、行を積まなかった点
    /// (既に滑走中・接線変位が零・両方が動かせない)は前の反復の乗数を保つ。前の反復の乗数は単精度の拘束が持つ。
    /// 参照計算は1つの反復の中だけを見るものであり、細分をまたいで積まれた乗数を自分で持たないためである。
    pub(in crate::contact) fn 一点の仮の接線の乗数(
        &self,
        拘束: &剛体と静的世界の接触拘束,
        点の番号: usize,
    ) -> 倍精度の三次元ベクトル {
        if !self.同時解.一点の法線の行が有効か(点の番号) {
            return 倍精度の三次元ベクトル::零();
        }
        let (x, y, z) = 拘束.静止摩擦の解の状態().接線のラグランジュ乗数().三つの成分();
        let 前の反復までの乗数 = 倍精度の三次元ベクトル::成分から生成する(f64::from(x.値()), f64::from(y.値()), f64::from(z.値()));
        match self.連立.接線の一行を読む(点の番号) {
            Some(接線の行) => 前の反復までの乗数.足す(&接線の行.接線の向き().比で伸ばす(self.同時解.一点の接線の乗数の増分(点の番号))),
            None => 前の反復までの乗数,
        }
    }

    /// 点ごとの接線変位の長さ C_t。行を持たない点は零である。
    pub(in crate::contact) fn 一点の接線変位の長さ(&self, 点の番号: usize) -> f64 {
        self.連立.接線の一行を読む(点の番号).map_or(0.0, |一行| 一行.接線変位の長さ())
    }
}
