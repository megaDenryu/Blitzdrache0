//! 倍精度の参照計算が1つの接触点集合について求めた解と、そこから読める診断の量(Issue #59)。
//! 連立を組んで相補条件を満たす有効集合を探し、勝った有効集合で抜き出しをもう一度作って、行ごとの残差と
//! 固有の向きの内訳を読めるようにした値である。
//! 抜き出しを作り直すのは、走査が候補ごとに抜き出しを捨てる工程であり、勝った1つを持ち帰らないためである。
//! 走査の側へ抜き出しを持ち帰らせないのは、走査が256個の候補を回るあいだ大きな行列を持ち回ることになるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

