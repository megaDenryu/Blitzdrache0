//! 倍精度の参照計算が定めた解の内訳(Issue #59が必須の診断行列に挙げた「擬似逆が捨てた固有の向きと理由」と
//! 「行ごとの残差」)。解そのもの(`reference_solution`)から分けているのは、あちらが乗数と拘束違反という
//! 物理の量を持ち、こちらが数値解法の内側の量だけを持つからである。
//! 固有の向きごとの内訳を別の型にするのは、1つの向きについて4つの値(固有値・右辺の射影・許容差の積み上がり・
//! 捨てた理由)が必ず揃って意味を持つためである。3つの並びを行の番号で突き合わせる形にすると、綴る側が
//! 3つの添字を揃える規律を毎回守ることになる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::super::super::symmetric_system::擬似逆が固有の向きを捨てた理由;
use super::reference_solution::倍精度の参照の解;

/// 擬似逆が扱った固有の向き1つの内訳。
pub(in crate::contact) struct 倍精度の固有の向きの内訳 {
    pub(in crate::contact) 固有値: f64,
    pub(in crate::contact) 右辺の射影: f64,
    pub(in crate::contact) 許容差の射影: f64,
    pub(in crate::contact) 捨てた理由: 擬似逆が固有の向きを捨てた理由,
}

/// 倍精度の参照計算が定めた解の、数値解法の内側の内訳。
pub(in crate::contact) struct 倍精度の解の内訳 {
    pub(in crate::contact) 有効集合のビット並び: u8,
    pub(in crate::contact) 行ごとの残差: Vec<f64>,
    pub(in crate::contact) 行ごとの解けたと見なす許容差: Vec<f64>,
    pub(in crate::contact) 固有の向きごと: Vec<倍精度の固有の向きの内訳>,
    pub(in crate::contact) 残差のノルム: f64,
}

impl 倍精度の参照の解 {
    /// 定めた解の数値解法の内側の内訳を読む。固有分解を組み直すのは、走査が候補ごとに分解を捨てるためである。
    pub(in crate::contact) fn 解の内訳を読む(&self) -> 倍精度の解の内訳 {
        let 行の数 = self.抜き出した.並び.行の数();
        let 分解 = self.抜き出した.固有分解する();
        let 固有の向きごと = (0..行の数)
            .map(|k| 倍精度の固有の向きの内訳 {
                固有値: 分解.第k番の固有値(k),
                右辺の射影: 分解.第k番の向きへの射影(k, &self.抜き出した.定数項),
                許容差の射影: 分解.第k番の向きへの許容差の射影(k, &self.抜き出した.行ごとの解けたと見なす許容差),
                捨てた理由: 分解.第k番の向きを捨てた理由(k, &self.抜き出した.定数項, &self.抜き出した.行ごとの解けたと見なす許容差),
            })
            .collect();
        倍精度の解の内訳 {
            有効集合のビット並び: self.有効集合.ビット並び(),
            行ごとの残差: (0..行の数).map(|k| self.抜き出した.第k行の残差(&self.擬似逆の解, k)).collect(),
            行ごとの解けたと見なす許容差: self.抜き出した.行ごとの解けたと見なす許容差[..行の数].to_vec(),
            固有の向きごと,
            残差のノルム: self.抜き出した.解いた行の残差と補正の大きさを測る(&self.擬似逆の解).残差のノルム(),
        }
    }
}
