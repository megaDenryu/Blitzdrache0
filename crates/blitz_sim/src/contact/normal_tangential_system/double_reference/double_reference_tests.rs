//! 単精度の本番の経路と倍精度の参照計算が、同じ入力から同じ量を返すことの試験(Issue #59)。
//! 担当するのは2つである。腕を持つ接触点1つの材料で、法線の拘束違反と接線変位と2つの乗数の増分の差が
//! 表現の刻みの桁に収まること、および同じ材料で有効集合と円錐の判定が一致することである。
//! 材料を1点にするのは、面と面の4点では連立の階数が足りず、どの乗数でも満たせない成分が差へ混ざるためである。
//! その成分は座標を倍精度にしても消えないため、2つの経路の一致を見る材料には使えない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

