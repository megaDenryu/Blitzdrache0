use super::super::super::contact_test_fixtures::{世界の位置を作る, 局所の変位を作る, 試験の刻み幅, 質量特性を作る};
use super::super::super::non_penetration::fixture::剛体と静的世界の基本の引数;
use super::super::接触点集合の法線と接線の連立;
