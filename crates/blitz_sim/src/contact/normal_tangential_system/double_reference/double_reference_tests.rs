// 箱の底面の半分の長さ。接触点をこれだけ重心の下へ置き、接線の力が重心まわりの回転を作る腕を持たせる。
const 底面の半分の長さ: f32 = 0.5;
// 初めの食い込み。法線の行が表現の刻みより深い右辺を持つ大きさに置く。
const 初めの食い込み: f32 = 1.0e-4;
// 錨をずらす長さ。接線変位がこの長さになる。
const 錨をずらす長さ: f32 = 1.0e-3;
// 2つの経路の差を、その量そのものの大きさで割った比の上限。単精度の相対の刻み1.2e-7の10倍を許す。
const 一致と見なす相対の差: f64 = 1.2e-6;

fn 試験の質量特性() -> 質量特性 {
    質量特性を作る(1.0, 1.0)
}

// 重心の下に接触点を持ち、錨だけを接平面の中でずらした接触点1つ。
fn 錨をずらした接触点一つ() -> (剛体と静的世界の接触拘束, 配置) {
    let 配置 = 配置::生成する(世界の位置を作る(0.0, -初めの食い込み, 0.0), 姿勢::恒等());
    let 引数 = 剛体と静的世界の接触拘束の引数 {
        剛体側の局所接触点: 局所の変位を作る(0.0, -底面の半分の長さ, 0.0),
        静的世界側の接触点: 世界の位置を作る(0.0, -底面の半分の長さ, 0.0),
        ..剛体と静的世界の基本の引数()
    };
    let mut 拘束 = 剛体と静的世界の接触拘束::引数と刻み幅から生成する(引数, 試験の刻み幅()).unwrap();
    拘束.開始した接触の錨を予測の前の配置へ置く(&配置::生成する(
        世界の位置を作る(錨をずらす長さ, -初めの食い込み, 0.0),
        姿勢::恒等(),
    ));
    (拘束, 配置)
}

// 単精度の本番の経路で同じ1点を解いた結果。行の積み方は本番の細分の工程と同じ2つの口を読む。
fn 単精度で解く(拘束: &剛体と静的世界の接触拘束, 配置: &配置) -> 接触点集合の法線と接線の連立 {
    let 参加者 = 姿勢自由度の参加者::動的(*配置, &試験の質量特性());
    let mut 連立 = 接触点集合の法線と接線の連立::点の数から空で始める(1);
    拘束.法線と接線の連立へ法線の一行を積む(0, &mut 連立, &参加者);
    拘束.法線と接線の連立へ接線の一行を積む(0, &mut 連立, &参加者);
    連立
}

// 2つの値の相対の差。分母が零に近い量では絶対の差をそのまま返す。
fn 相対の差(単精度: f64, 倍精度: f64) -> f64 {
    let 分母 = 倍精度.abs().max(単精度.abs());
    if 分母 > 0.0 { (単精度 - 倍精度).abs() / 分母 } else { 0.0 }
}

#[test]
fn 接触点一つでは単精度と倍精度の拘束違反と乗数の増分が表現の刻みの桁で一致する() {
    let (拘束, 配置) = 錨をずらした接触点一つ();
    let 単精度の連立 = 単精度で解く(&拘束, &配置);
    let 単精度の解 = 単精度の連立.相補条件を満たす有効集合で同時に解く().定まった解を取り出す();
    let 倍精度の参照の結末::解が定まった(参照の解) =
        倍精度の参照の結末::単精度の接触点集合から求める(&[拘束], &配置, &試験の質量特性())
    else {
        panic!("倍精度の参照計算が接触点1つの材料で解を定められなかった");
    };
    let 法線の行 = 単精度の連立.法線の一行を読む(0).unwrap();
    let 接線の行 = 単精度の連立.接線の一行を読む(0).unwrap();
    for (名前, 単精度, 倍精度) in [
        ("法線の拘束違反", f64::from(法線の行.隔たり().値()), 参照の解.一点の法線の拘束違反(0)),
        ("接線変位", f64::from(接線の行.接線変位の長さ().値()), 参照の解.一点の接線変位の長さ(0)),
        (
            "法線の乗数の増分",
            f64::from(単精度の解.一点の法線の乗数の増分(0).値()),
            参照の解.同時解.一点の法線の乗数の増分(0),
        ),
        (
            "接線の乗数の増分",
            f64::from(単精度の解.一点の接線の乗数の増分(0).値()),
            参照の解.同時解.一点の接線の乗数の増分(0),
        ),
    ] {
        let 差 = 相対の差(単精度, 倍精度);
        assert!(差 <= 一致と見なす相対の差, "{名前}が単精度{単精度}と倍精度{倍精度}で相対{差}離れた");
    }
}

#[test]
fn 接触点一つでは単精度と倍精度の有効集合と円錐の判定が一致する() {
    let (拘束, 配置) = 錨をずらした接触点一つ();
    let 単精度の解 = 単精度で解く(&拘束, &配置).相補条件を満たす有効集合で同時に解く().定まった解を取り出す();
    let 倍精度の参照の結末::解が定まった(参照の解) =
        倍精度の参照の結末::単精度の接触点集合から求める(&[拘束], &配置, &試験の質量特性())
    else {
        panic!("倍精度の参照計算が接触点1つの材料で解を定められなかった");
    };
    assert_eq!(
        単精度の解.一点の法線の行が有効か(0),
        参照の解.同時解.一点の法線の行が有効か(0),
        "法線の有効集合が2つの経路で違う"
    );
    let 判定 = 倍精度の円錐の判定::参照の解と単精度の接触点集合から集計する(&参照の解, &[拘束]);
    assert!(判定.法線の乗数の合計() > 0.0, "参照計算の法線の乗数の合計が正でない");
    assert!(
        判定.合力と法線の合計の比() > 0.0,
        "参照計算の接線の合力と法線の合計の比が正でない: {}",
        判定.合力と法線の合計の比()
    );
}
