//! 倍精度の擬似逆で解く工程と、その結果(Issue #59の数値契約の診断)。単精度の`pseudo_inverse`と同じ2つの
//! 判定を同じ順で行う。行列の側は分解そのものの丸めが作る偽の固有値を λ_k ≤ λ_max n ε で落とし、右辺の側は
//! |β_k| ≤ δ_k の向きを落とす。違うのは ε が倍精度のものであることと、δ_k が倍精度の表現の刻みから来ることだけである。
//! この2つを倍精度にすると、単精度の側が「解けたと見なして捨てた」向きの大半が参照計算では捨てられない。
//! その差がそのまま、許容差という取り決めが物理の判定へ持ち込んでいる量になる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::super::super::symmetric_system::{擬似逆が固有の向きを捨てた理由, 法線と接線の連立の行の上限};
use super::jacobi::倍精度の対称な連立の固有分解;

// 分解そのものの丸めが作る偽の固有値の比。次数 n の対称行列をヤコビ法で分解したときの固有値の誤差の桁が n ε である。
const 次数の上界: f64 = 16.0;

/// 倍精度の擬似逆で解いた結果。増分と、許容差の内側として捨てた右辺の行ごとの成分を持つ。
pub(in crate::contact) struct 倍精度の擬似逆で解いた増分と捨てた右辺 {
    増分: [f64; 法線と接線の連立の行の上限],
    許容差の内側として捨てた右辺: [f64; 法線と接線の連立の行の上限],
}

impl 倍精度の擬似逆で解いた増分と捨てた右辺 {
    pub(in crate::contact) fn 増分(&self) -> &[f64; 法線と接線の連立の行の上限] {
        &self.増分
    }

    /// 第k行が受け取る、許容差の内側として捨てた右辺の成分。行ごとの許容差と比べる対象である。
    pub(in crate::contact) fn 第k行の許容差の内側として捨てた右辺(&self, k: usize) -> f64 {
        self.許容差の内側として捨てた右辺[k]
    }
}

impl 倍精度の対称な連立の固有分解 {
    /// 偽の固有値の向きと、許容差の内側にしかない右辺の向きを捨てた擬似逆の解。
    pub(in crate::contact) fn 擬似逆で解く(
        &self,
        定数項: &[f64; 法線と接線の連立の行の上限],
        行ごとの解けたと見なす許容差: &[f64; 法線と接線の連立の行の上限],
    ) -> 倍精度の擬似逆で解いた増分と捨てた右辺 {
        let 偽の固有値の下限 = self.偽の固有値の下限();
        let mut 増分 = [0.0; 法線と接線の連立の行の上限];
        let mut 許容差の内側として捨てた右辺 = [0.0; 法線と接線の連立の行の上限];
        for (k, 固有値) in self.固有値.iter().enumerate().take(self.個数) {
            let 右辺の射影 = self.第k番の向きへの射影(k, 定数項);
            if *固有値 <= 偽の固有値の下限 {
                continue;
            }
            if 右辺の射影.abs() <= self.第k番の向きへの許容差の射影(k, 行ごとの解けたと見なす許容差) {
                self.第k番の向きの成分を足し込む(&mut 許容差の内側として捨てた右辺, k, 右辺の射影);
                continue;
            }
            self.第k番の向きの成分を足し込む(&mut 増分, k, 右辺の射影 / 固有値);
        }
        倍精度の擬似逆で解いた増分と捨てた右辺 {
            増分,
            許容差の内側として捨てた右辺,
        }
    }

    /// 第k番の固有の向きを捨てたかと、捨てたならその理由。診断の表が単精度の側の理由と並べて綴る。
    pub(in crate::contact) fn 第k番の向きを捨てた理由(
        &self,
        k: usize,
        定数項: &[f64; 法線と接線の連立の行の上限],
        行ごとの解けたと見なす許容差: &[f64; 法線と接線の連立の行の上限],
    ) -> 擬似逆が固有の向きを捨てた理由 {
        if self.固有値[k] <= self.偽の固有値の下限() {
            return 擬似逆が固有の向きを捨てた理由::偽の固有値;
        }
        if self.第k番の向きへの射影(k, 定数項).abs() <= self.第k番の向きへの許容差の射影(k, 行ごとの解けたと見なす許容差)
        {
            return 擬似逆が固有の向きを捨てた理由::右辺が許容差の内側;
        }
        擬似逆が固有の向きを捨てた理由::捨てていない
    }

    /// 第k番の固有ベクトルへの右辺の射影 β_k = v_kᵀ b。
    pub(in crate::contact) fn 第k番の向きへの射影(&self, k: usize, 定数項: &[f64; 法線と接線の連立の行の上限]) -> f64 {
        self.固有ベクトルの列
            .iter()
            .zip(定数項.iter())
            .take(self.個数)
            .map(|(第i行, 定数)| 第i行[k] * 定数)
            .sum()
    }

    /// 第k番の固有ベクトルの向きへ行ごとの許容差を積み上げた大きさ δ_k = √(Σ_i (v_ik δ_i)²)。
    pub(in crate::contact) fn 第k番の向きへの許容差の射影(
        &self,
        k: usize,
        行ごとの解けたと見なす許容差: &[f64; 法線と接線の連立の行の上限],
    ) -> f64 {
        self.固有ベクトルの列
            .iter()
            .zip(行ごとの解けたと見なす許容差.iter())
            .take(self.個数)
            .map(|(第i行, 許容差)| (第i行[k] * 許容差) * (第i行[k] * 許容差))
            .sum::<f64>()
            .sqrt()
    }

    // 受け皿へ 係数 v_k を足し込む。解と捨てた右辺のどちらも同じ形の積み上げである。
    fn 第k番の向きの成分を足し込む(&self, 受け皿: &mut [f64; 法線と接線の連立の行の上限], k: usize, 係数: f64) {
        for (値, 第i行) in 受け皿.iter_mut().zip(self.固有ベクトルの列.iter()).take(self.個数) {
            *値 += 係数 * 第i行[k];
        }
    }

    // 分解そのものの丸めが作る偽の固有値の下限 λ_max n ε。
    fn 偽の固有値の下限(&self) -> f64 {
        self.固有値の最大() * 次数の上界 * f64::EPSILON
    }

    fn 固有値の最大(&self) -> f64 {
        (0..self.個数).map(|k| self.固有値[k]).fold(0.0, f64::max)
    }
}
