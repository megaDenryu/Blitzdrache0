//! 有効集合から外した接触点の法線の乗数を零へ解放する増分が、有効な行の右辺の量をどれだけ動かすかを測る工程
//! (Issue #59の数値契約の診断)。抜き出しが定数項からこの長さを引く。
//! 抜き出し(`reduced_system`)から分けているのは、あちらが行列と右辺と許容差を組む工程であり、こちらが
//! 「連立から外れた点が残った行へ及ぼす分」という別の概念を1つ持つからである。単精度の側と同じく連立の
//! メソッドであり、ファイルだけを分けている。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

#![cfg(test)]

use super::active_set::倍精度の連立の有効集合;
use super::gradient::倍精度の一行の二つの符号付き勾配;
use super::manifold_system::倍精度の接触点集合の連立;

impl 倍精度の接触点集合の連立 {
    /// 外した点の解放の増分が、渡した行の右辺の量を動かす長さ Σ_{j∉A} W_ij Δλ_j。
    pub(in crate::contact) fn 外した点の解放が動かす長さ(
        &self,
        行の勾配: &倍精度の一行の二つの符号付き勾配,
        有効集合: &倍精度の連立の有効集合,
    ) -> f64 {
        let mut 合計 = 0.0;
        for 点の番号 in (0..self.点の数()).filter(|番号| !有効集合.有効か(*番号)) {
            if let Some(法線の行) = self.法線の一行を読む(点の番号) {
                合計 += self.外した点の法線の乗数を解放する増分(点の番号) * 行の勾配.交差の寄与(法線の行.勾配());
            }
        }
        合計
    }
}
