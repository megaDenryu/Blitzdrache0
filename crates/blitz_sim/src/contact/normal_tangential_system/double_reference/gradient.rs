//! 倍精度の、連立の1行が2つの参加者へ与える符号付きの勾配(Issue #59の数値契約の診断)。単精度の
//! `一行の二つの符号付き勾配`と同じ式を倍精度で書いたものであり、法線の行も接線の行もこの型で交差の項を組む。
//! 参加者ごとの符号を型が持つ理由は単精度の側と同じである。法線と接線の交差の項の符号は「どちらの参加者から
//! 見た勾配か」で決まり、向きを1つだけ持つ形では法線どうしの符号が打ち消し合って誤りが見えなくなる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::participant_point::倍精度の接触の射影に参加する点;
use super::vector::倍精度の三次元ベクトル;

/// 倍精度の、1行が持つ2つの参加者に対する符号付きの勾配。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 倍精度の一行の二つの符号付き勾配 {
    第1の参加点: 倍精度の接触の射影に参加する点,
    第1の勾配の向き: 倍精度の三次元ベクトル,
    第2の参加点: 倍精度の接触の射影に参加する点,
    第2の勾配の向き: 倍精度の三次元ベクトル,
}

impl 倍精度の一行の二つの符号付き勾配 {
    /// 法線の行の勾配。拘束は隔たり d = (p_2 − p_1)·n であり、勾配は第1へ −n、第2へ +n である。
    pub(in crate::contact) fn 法線の行として生成する(
        第1の接触点: 倍精度の接触の射影に参加する点,
        第2の接触点: 倍精度の接触の射影に参加する点,
        接触法線: 倍精度の三次元ベクトル,
    ) -> Self {
        Self {
            第1の参加点: 第1の接触点,
            第1の勾配の向き: 接触法線.比で伸ばす(-1.0),
            第2の参加点: 第2の接触点,
            第2の勾配の向き: 接触法線,
        }
    }

    /// 接線の行の勾配。拘束は接線変位 Δ_t = a_1 − a_2 の長さであり、勾配は第1へ +t、第2へ −t である。
    pub(in crate::contact) fn 接線の行として生成する(
        第1の錨: 倍精度の接触の射影に参加する点,
        第2の錨: 倍精度の接触の射影に参加する点,
        接線の向き: 倍精度の三次元ベクトル,
    ) -> Self {
        Self {
            第1の参加点: 第1の錨,
            第1の勾配の向き: 接線の向き,
            第2の参加点: 第2の錨,
            第2の勾配の向き: 接線の向き.比で伸ばす(-1.0),
        }
    }

    /// この行と相手の行が2つの参加者を通して結び付く量 J_i M⁻¹ J_jᵀ。同じ行を2度渡せば対角の成分になる。
    pub(in crate::contact) fn 交差の寄与(&self, 相手: &Self) -> f64 {
        self.第1の参加点
            .二つの点の一般化逆質量の交差の寄与(&self.第1の勾配の向き, &相手.第1の参加点, &相手.第1の勾配の向き)
            + self
                .第2の参加点
                .二つの点の一般化逆質量の交差の寄与(&self.第2の勾配の向き, &相手.第2の参加点, &相手.第2の勾配の向き)
    }

    /// この行の右辺を解けたと見なす許容差。倍精度の座標の表現の刻みから決まる。
    pub(in crate::contact) fn 解けたと見なす許容差(&self) -> f64 {
        self.第1の参加点
            .二つの点の世界位置の差を向きへ射影した解けたと見なす許容差(&self.第2の参加点, &self.第1の勾配の向き)
    }

    /// 2つの参加点の世界位置の差を第2の勾配の向きへ射影した長さ (p_2 − p_1)·g_2。法線の行ではこれが隔たりである。
    pub(in crate::contact) fn 第2の勾配の向きへ射影した二つの点の世界位置の差(&self) -> f64 {
        self.第2の参加点.世界位置().引く(&self.第1の参加点.世界位置()).内積(&self.第2の勾配の向き)
    }

    /// どちらの参加者も動かせない行か。この行は連立から外す。
    pub(in crate::contact) fn 動かせない組か(&self) -> bool {
        self.第1の参加点.動かせないか() && self.第2の参加点.動かせないか()
    }
}
