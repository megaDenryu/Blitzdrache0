//! 単精度と倍精度の拘束違反が、行の許容差の内側で一致することの試験(Issue #59)。
//! 長さの量(法線の拘束違反と接線変位)は、差を相対で見ずにその行の解けたと見なす許容差と比べる。単精度の
//! 加算1回の丸めは、隔たり1e-4に対して相対1.7e-4に達する一方、世界位置0.5の表現の刻みの半分には収まる。
//! 相対で見ると「小さい量ほど厳しく測る」ことになり、差が丸めであることを判定できない。
//! 乗数の増分と円錐の判定は`multiplier_tests`が固定する。分けているのは、こちらが行の右辺の材料になる長さを
//! 見るのに対し、あちらが連立を解いた後の値を見るからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::double_reference_fixture::{
    単精度の連立を組む, 許容差を据え置いて倍精度で解く, 錨をずらした接触点一つを組む
};

#[test]
fn 接触点一つでは単精度と倍精度の拘束違反が行の許容差の内側で一致する() {
    let (拘束, 配置) = 錨をずらした接触点一つを組む();
    let 単精度の連立 = 単精度の連立を組む(&拘束, &配置);
    let 参照の解 = 許容差を据え置いて倍精度で解く(拘束, &配置);
    let 法線の行 = 単精度の連立.法線の一行を読む(0).unwrap();
    let 接線の行 = 単精度の連立.接線の一行を読む(0).unwrap();
    for (名前, 単精度, 倍精度, 許容差) in [
        (
            "法線の拘束違反",
            f64::from(法線の行.隔たり().値()),
            参照の解.一点の法線の拘束違反(0),
            f64::from(法線の行.隔たりの表現の刻み().値()),
        ),
        (
            "接線変位",
            f64::from(接線の行.接線変位の長さ().値()),
            参照の解.一点の接線変位の長さ(0),
            f64::from(接線の行.勾配().解けたと見なす許容差().値()),
        ),
    ] {
        let 差 = (単精度 - 倍精度).abs();
        assert!(
            差 <= 許容差,
            "{名前}が単精度{単精度}と倍精度{倍精度}で{差}離れ、行の許容差{許容差}を超えた"
        );
    }
}
