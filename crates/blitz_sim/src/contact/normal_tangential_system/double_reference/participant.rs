//! 倍精度の姿勢自由度の参加者(Issue #59の数値契約の診断)。単精度の`姿勢自由度の参加者`と同じ3つ(配置・逆質量・
//! ワールドの逆慣性)を倍精度で持つ。
//! この型を置くのは、配置と質量特性が常に揃って参照計算の呼び出し境界を越えるためである。2つを別々に運ぶと、
//! 参加点を作る口・法線の行を組む口・接線の行を組む口のすべてが同じ2引数を並べて受け取ることになり、
//! 片方だけ別の剛体のものを渡す組み合わせが型の上で表現できてしまう。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断9: 拘束の勾配から並進と回転の補正を一般化逆質量で分配し、確定後に速度と角速度を再構成する」

#![cfg(test)]

use super::inverse_inertia::倍精度のワールドの逆慣性;
use super::placement::倍精度の剛体の配置;
use super::vector::倍精度の三次元ベクトル;
use crate::rigid_body::{質量特性, 配置};

/// 倍精度の、拘束の射影が読む剛体の3つの量。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 倍精度の姿勢自由度の参加者 {
    配置: 倍精度の剛体の配置,
    逆質量: f64,
    ワールドの逆慣性: 倍精度のワールドの逆慣性,
}

impl 倍精度の姿勢自由度の参加者 {
    /// 動的剛体。単精度の配置と質量特性を倍精度へ広げ、ワールドの逆慣性をこの配置の姿勢で組み直す。
    pub(in crate::contact) fn 単精度の配置と質量特性から広げる(配置: &配置, 質量特性: &質量特性) -> Self {
        let 倍精度の配置 = 倍精度の剛体の配置::単精度の配置から広げる(配置);
        Self {
            逆質量: f64::from(質量特性.逆質量().値()),
            ワールドの逆慣性: 倍精度のワールドの逆慣性::質量特性と姿勢から組む(質量特性, 倍精度の配置.姿勢()),
            配置: 倍精度の配置,
        }
    }

    /// 静的世界の接触相手。実効の重みが零であり、補正を受けない。配置は使われないため恒等の姿勢で足りる。
    pub(in crate::contact) fn 動かせない(配置: 倍精度の剛体の配置) -> Self {
        Self {
            配置,
            逆質量: 0.0,
            ワールドの逆慣性: 倍精度のワールドの逆慣性::零(),
        }
    }

    pub(in crate::contact) fn 配置(&self) -> 倍精度の剛体の配置 {
        self.配置
    }

    pub(in crate::contact) fn 逆質量(&self) -> f64 {
        self.逆質量
    }

    /// 2つの点に別々の向きで作用する2つの拘束が、この剛体を通して結び付く一般化逆質量の交差の寄与
    /// w (n₁·n₂) + (r₁ × n₁)ᵀ I⁻¹ (r₂ × n₂)。
    pub(in crate::contact) fn 二つの腕と向きの一般化逆質量の交差の寄与(
        &self,
        第1の腕: &倍精度の三次元ベクトル,
        第1の向き: &倍精度の三次元ベクトル,
        第2の腕: &倍精度の三次元ベクトル,
        第2の向き: &倍精度の三次元ベクトル,
    ) -> f64 {
        let 第1の外積 = 第1の腕.外積(第1の向き);
        let 第2の外積 = 第2の腕.外積(第2の向き);
        self.逆質量 * 第1の向き.内積(第2の向き) + 第1の外積.内積(&self.ワールドの逆慣性.ベクトルへ作用させる(&第2の外積))
    }
}
