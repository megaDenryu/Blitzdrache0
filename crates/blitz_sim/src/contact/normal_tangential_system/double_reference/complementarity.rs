//! 倍精度の、1つの有効集合の解が法線の相補条件を満たすかの判定(Issue #59の数値契約の診断)。
//! 単精度の`complementarity`と同じ3つを同じ式で判定する。有効な点の更新後の法線の乗数が0以上であること、
//! その乗数がこの細分に詰めてよい長さから決まる上限を超えないこと、有効でない点の更新後の隔たりが表現の刻みを
//! 超えて負でないことである。
//! 隔たりの表現の刻みは単精度のものを使う(理由は`widened_normal_state`にある)。
//! 増分が隔たりを動かす長さを別のメソッドへ切り出さないのは、それが食い込みの判定の中でしか意味を持たない
//! 途中の量であり、連立の型が持つ口を1つ増やすほどの概念ではないためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

#![cfg(test)]

use super::active_set::倍精度の連立の有効集合;
use super::manifold_system::倍精度の接触点集合の連立;
use super::solution::倍精度の接触点集合の同時解;

impl 倍精度の接触点集合の連立 {
    /// この解が法線の相補条件を満たすか。満たさない集合は候補にしない。
    pub(in crate::contact) fn 相補条件を満たすか(
        &self, 同時解: &倍精度の接触点集合の同時解, 有効集合: &倍精度の連立の有効集合
    ) -> bool {
        (0..self.点の数()).all(|点の番号| {
            if 有効集合.有効か(点の番号) {
                self.有効な点の乗数が範囲に収まるか(同時解, 点の番号)
            } else {
                !self.補正の後に食い込むか(同時解, 点の番号)
            }
        })
    }

    // 有効な点の更新後の法線の乗数が0以上で、この細分の乗数の上限も超えないか。
    fn 有効な点の乗数が範囲に収まるか(&self, 同時解: &倍精度の接触点集合の同時解, 点の番号: usize) -> bool {
        self.法線の一行を読む(点の番号).is_some_and(|一行| {
            let 更新後 = 一行.法線のラグランジュ乗数() + 同時解.一点の法線の乗数の増分(点の番号);
            更新後 >= 0.0 && 更新後 <= 一行.乗数の上限()
        })
    }

    // 有効でない点が、求めた増分を適用してもなお表現の刻みを超えて食い込むか。
    // 増分がこの点の隔たりを動かす長さ Σ_j W_ij Δλ_j をこの中で数える。有効でない点の解放の増分も含む。
    fn 補正の後に食い込むか(&self, 同時解: &倍精度の接触点集合の同時解, 点の番号: usize) -> bool {
        let Some(自分) = self.法線の一行を読む(点の番号) else {
            return false;
        };
        if 自分.動かせない組か() {
            return false;
        }
        let mut 増分が動かす隔たり = 0.0;
        for 相手の番号 in 0..self.点の数() {
            if let Some(法線の行) = self.法線の一行を読む(相手の番号) {
                増分が動かす隔たり += 同時解.一点の法線の乗数の増分(相手の番号) * 自分.勾配().交差の寄与(法線の行.勾配());
            }
            if let Some(接線の行) = self.接線の一行を読む(相手の番号) {
                増分が動かす隔たり += 同時解.一点の接線の乗数の増分(相手の番号) * 自分.勾配().交差の寄与(接線の行.勾配());
            }
        }
        自分.隔たり() + 増分が動かす隔たり < -自分.隔たりの表現の刻み()
    }
}
