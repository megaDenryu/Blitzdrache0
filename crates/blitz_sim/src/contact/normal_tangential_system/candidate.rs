//! 相補条件を満たした1つの有効集合と、その解(判断12・判断13)。部分集合を走査する側(`subset_search`)が、
//! 条件を満たした集合ごとにこの値を作り、決着の順で1つへ絞る。
//! 決着の順は4段である。まず有効な点の数が多い方、次に解いた行の残差、次に補正の質量の計量のノルム、最後に
//! 有効集合のビット並びである。
//! 有効な点の数を先に見るのは、面と面の接触の相補問題が構造として退化しているからである。剛体は法線方向に
//! 3つの自由度しか持たないため、4点の隔たりのうち3点を止めれば残る1点も動かない。したがって「1点を外して
//! 残る3点で解く」候補も相補条件を満たし、しかも行の数が自由度と釣り合うぶん残差が小さくなる。残差だけで
//! 選ぶとこの候補が勝ち、外した点の接線の乗数が零へ解放されて、集合の接線の合力が点の数のぶんだけ落ちる
//! (4点の材料で実測4分の1。傾きの正接0.40の坂で合力の比が0.40から0.30へ落ちた)。
//! 触れている点は反力を持つ、というのが法線の有効集合の意味であり、退化した候補の中ではそれを保つ集合を採る。
//! 有効な点の数が第1の鍵であることが、走査を有効な点の数の階層で打ち切ってよい根拠でもある(`subset_search`)。
//! この鍵の順を入れ替えると打ち切りが結果を変えるため、順を変えるときは階層の走査と全走査の一致の検査が落ちる。
//! 最後にビット並びまで要るのは、乗数も増分も零の点を入れた集合と外した集合が同じ解を返す退化があるためである。
//! 解の型(`solution`)から分けているのは、あちらが点ごとの増分そのものであり、こちらがその解を選ぶための材料を
//! 添えた候補だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use std::cmp::Ordering;

use super::active_set::法線と接線の連立の有効集合;
use super::solution::接触点集合の法線と接線の同時解;
use super::solved_quality::解いた行の残差と補正の大きさ;

/// 相補条件を満たした1つの有効集合の解と、決着に使う材料。
pub(super) struct 相補条件を満たした候補 {
    同時解: 接触点集合の法線と接線の同時解,
    質: 解いた行の残差と補正の大きさ,
    有効集合: 法線と接線の連立の有効集合,
}

impl 相補条件を満たした候補 {
    pub(super) fn 解と質と有効集合から組む(
        同時解: 接触点集合の法線と接線の同時解,
        質: 解いた行の残差と補正の大きさ,
        有効集合: 法線と接線の連立の有効集合,
    ) -> Self {
        Self {
            同時解, 質, 有効集合
        }
    }

    pub(super) fn 同時解(&self) -> 接触点集合の法線と接線の同時解 {
        self.同時解
    }

    /// この候補が表す有効集合。
    /// 注意: 階層の走査と全走査の一致を突き合わせる検査だけの口である。決着はこの型の中で閉じている。
    #[cfg(test)]
    pub(super) fn 有効集合(&self) -> 法線と接線の連立の有効集合 {
        self.有効集合
    }

    /// この候補が要求の精度で解けているか。偽なら呼び出し側は表現の精度の不足として扱う。
    pub(super) fn 全部の行の残差が許容差の内側か(&self) -> bool {
        self.質.全部の行の残差が許容差の内側か()
    }

    /// 2つの候補のうち先に選ぶ方。有効な点の数・残差・補正の質量の計量のノルム・ビット並びの順で比べ、
    /// 全部が同じなら自分を残す。
    pub(super) fn 先に選ぶ方を採る(self, 相手: Self) -> Self {
        match self.先に選ぶ順で比べる(&相手) {
            Ordering::Greater => 相手,
            Ordering::Less | Ordering::Equal => self,
        }
    }

    // 有効な点の数だけは多い方を先に選ぶため、比べる向きを逆にする。
    fn 先に選ぶ順で比べる(&self, 相手: &Self) -> Ordering {
        相手
            .有効集合
            .点の数を数える()
            .cmp(&self.有効集合.点の数を数える())
            .then_with(|| self.質.先に選ぶ順で比べる(&相手.質))
            .then_with(|| self.有効集合.cmp(&相手.有効集合))
    }
}
