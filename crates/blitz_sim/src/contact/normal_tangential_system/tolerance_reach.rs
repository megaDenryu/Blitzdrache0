//! 受理の倍率が届く先と、接線の行を積む閾値の倍率(判断13、Issue #59の第4段階の段階C。試験と計器の専用)。
//! 本番の受理の倍率は1倍であり、試験の倍率は擬似逆が固有の向きを捨てる閾値と受理の判定(A・B1・B4)の両方へ掛かる。
//! 遠方の正接0.58が受理2倍で滑走した原因が、擬似逆の採否(候補Eの領域)か受理の判定の配線かを分けるために、倍率を
//! 受理の判定だけへ届かせる枝を置く。行を積む閾値の倍率は、閾値のすぐ外側の行(C_t/δ = 1.0〜3.3)の退避が累積して
//! 滑走を作る事象を、閾値の帯 k δ で消せるかを測るための枝である。どちらも本番の既定ではない(親の2026-09-12の指示)。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

/// 受理の倍率がどこまで届くか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 受理の倍率の届く先 {
    /// 擬似逆が固有の向きを捨てる閾値と、受理の判定の両方へ掛ける(改訂の前からの形)。
    擬似逆の採否と受理の判定,
    /// 受理の判定(A・B1・B4の比較)だけへ掛け、擬似逆が向きを捨てる閾値には掛けない。
    受理の判定だけ,
}

/// 接線の行を積む閾値 k δ の k。本番は1である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 行を積む閾値の倍率 {
    比: f32,
}

impl 行を積む閾値の倍率 {
    pub fn 既定で生成する() -> Self {
        Self { 比: 1.0 }
    }

    pub fn 比から生成する(比: f32) -> Self {
        Self { 比 }
    }

    pub fn 比(&self) -> f32 {
        self.比
    }
}
