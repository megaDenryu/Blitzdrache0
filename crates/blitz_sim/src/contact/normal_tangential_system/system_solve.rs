//! 法線と接線の連立を有効集合を組み替えながら解く工程(判断12・判断13)。連立の定義(`system`)から分けているのは、
//! 行を積むのが接触点集合の走査1回であるのに対し、この工程が抜き出しと求解を繰り返す別の局面だからである。
//! 組み替えは2つの向きを持つ。更新後の法線の乗数が負に振れた点を外し、外した点の補正の後の隔たりが表現の刻みを
//! 超えて負なら入れ直す。負の行を外すだけでは足りない。混合の補正は法線の荷重を移すため、いま乗数が零の点が
//! 食い込むことがある。外した点の法線の乗数は零へ解放し、その解放が動かす長さを残る行の右辺から引く。
//! 走査は接触点の番号の昇順で行い、最初に見つかった点を選ぶ(同じ入力から同じ解が出るためである)。
//! 2つの向きがあるため同じ点が何度も出入りしうる。終了は回数の上限でなく、通った有効集合の記録で保証する
//! (`visited_active_set`)。同じ集合へ戻ったら解は定まっておらず、巡回した枝を返す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::メートル;

use super::active_set::法線と接線の連立の有効集合;
use super::reduced_system::有効な行だけを抜き出した連立;
use super::solution::接触点集合の法線と接線の同時解;
use super::solve_outcome::有効集合を組み替えて解いた結末;
use super::system::接触点集合の法線と接線の連立;
use super::visited_active_set::通った有効集合の記録;
use crate::rigid_xpbd::姿勢自由度の補正;
use crate::xpbd::ラグランジュ乗数;

impl 接触点集合の法線と接線の連立 {
    /// 積んだ行を1つの連立として解いた点ごとの増分。有効集合の組み替えが止まるまで解き直す。
    /// 一度通った集合へ戻ったら組み替えが巡回しており、解が定まらない枝を返す。
    pub fn 同時に解く(&self) -> 有効集合を組み替えて解いた結末 {
        let mut 通った記録 = 通った有効集合の記録::空();
        let mut 有効集合 = self.押し戻す点から始める有効集合();
        while 通った記録.初めて通るなら印す(&有効集合) {
            let 同時解 = self.有効集合で解く(&有効集合);
            if let Some(点の番号) = self.法線の乗数が負になる最初の点(&同時解) {
                有効集合.外す(点の番号);
            } else if let Some(点の番号) = self.補正の後に食い込む最初の点(&同時解, &有効集合) {
                有効集合.入れる(点の番号);
            } else {
                self.組み替えが止まった解を再検査する(&同時解, &有効集合);
                return 有効集合を組み替えて解いた結末::有効集合が定まった(同時解);
            }
        }
        有効集合を組み替えて解いた結末::有効集合の組み替えが巡回した
    }

    // 組み替えが止まった解が満たすべき2つの条件を全部の点で確かめる。有効な点の更新後の法線の乗数が負でないことと、
    // 外れた点が表現の刻みを超えて食い込んでいないことである。
    // 注意: この2つは組み替えの止まる条件そのものであるため、破れたらこの工程のバグである。
    fn 組み替えが止まった解を再検査する(
        &self, 同時解: &接触点集合の法線と接線の同時解, 有効集合: &法線と接線の連立の有効集合
    ) {
        if let Some(点の番号) = self.法線の乗数が負になる最初の点(同時解) {
            panic!("組み替えが止まった解に負の法線の乗数が残った: 点{点の番号}");
        }
        if let Some(点の番号) = self.補正の後に食い込む最初の点(同時解, 有効集合) {
            panic!("有効集合から外れた点が表現の刻みを超えて食い込んだままである: 点{点の番号}");
        }
    }

    /// 求めた増分が剛体(第1の参加者)へ与える補正の合計。点ごとに配置へ適用すると次の点の腕と有効逆質量が
    /// 変わるため、呼び出し側はこの合計を1度だけ適用する。
    pub fn 第1の参加者への補正の合計(&self, 同時解: &接触点集合の法線と接線の同時解) -> 姿勢自由度の補正 {
        let mut 合計 = 姿勢自由度の補正::零();
        for 点の番号 in 0..self.点の数() {
            if let Some(法線の行) = self.法線の一行を読む(点の番号) {
                let 増分 = 同時解.一点の法線の乗数の増分(点の番号);
                合計 = 合計.合わせる(&法線の行.勾配().乗数の増分を第1の参加者の補正へ分配する(増分));
            }
            if let Some(接線の行) = self.接線の一行を読む(点の番号) {
                let 増分 = 同時解.一点の接線の乗数の増分(点の番号);
                合計 = 合計.合わせる(&接線の行.勾配().乗数の増分を第1の参加者の補正へ分配する(増分));
            }
        }
        合計
    }

    // 押し戻している点だけを入れた開始の有効集合。判断12の有効集合の開始の定義と同じ式である。
    fn 押し戻す点から始める有効集合(&self) -> 法線と接線の連立の有効集合 {
        let mut 有効集合 = 法線と接線の連立の有効集合::空();
        for 点の番号 in 0..self.点の数() {
            if self.法線の一行を読む(点の番号).is_some_and(|一行| 一行.押し戻しているか()) {
                有効集合.入れる(点の番号);
            }
        }
        有効集合
    }

    fn 有効集合で解く(&self, 有効集合: &法線と接線の連立の有効集合) -> 接触点集合の法線と接線の同時解 {
        有効な行だけを抜き出した連立::抜き出す(self, 有効集合).解いてもとの点へ戻す(self, 有効集合)
    }

    // 有効な点のうち、更新後の法線の乗数が負に振れた最初の点。
    fn 法線の乗数が負になる最初の点(&self, 同時解: &接触点集合の法線と接線の同時解) -> Option<usize> {
        (0..self.点の数()).find(|点の番号| {
            同時解.一点の法線の行が有効か(*点の番号)
                && self
                    .法線の一行を読む(*点の番号)
                    .is_some_and(|一行| 一行.既存の法線の乗数() + 同時解.一点の法線の乗数の増分(*点の番号) < ラグランジュ乗数::零())
        })
    }

    // 有効でない点のうち、求めた増分を適用してもなお食い込む最初の点。
    fn 補正の後に食い込む最初の点(
        &self,
        同時解: &接触点集合の法線と接線の同時解,
        有効集合: &法線と接線の連立の有効集合,
    ) -> Option<usize> {
        (0..self.点の数()).find(|点の番号| {
            !有効集合.有効か(*点の番号)
                && self.法線の一行を読む(*点の番号).is_some_and(|一行| {
                    !一行.勾配().動かせない組か()
                        && 一行.表現の刻みを超えて食い込むか(一行.隔たり() + self.増分が動かす隔たり(*点の番号, 同時解))
                })
        })
    }

    // 求めた増分がこの点の法線の隔たりを動かす長さ Σ_j W_ij Δλ_j。入れ直す点を拾うために読む。
    fn 増分が動かす隔たり(&self, 点の番号: usize, 同時解: &接触点集合の法線と接線の同時解) -> メートル {
        let Some(自分) = self.法線の一行を読む(点の番号) else {
            return メートル::生成する(0.0);
        };
        let mut 合計 = メートル::生成する(0.0);
        for 相手の番号 in 0..self.点の数() {
            if let Some(法線の行) = self.法線の一行を読む(相手の番号) {
                合計 = 合計 + 同時解.一点の法線の乗数の増分(相手の番号) * 自分.勾配().交差の寄与(法線の行.勾配());
            }
            if let Some(接線の行) = self.接線の一行を読む(相手の番号) {
                合計 = 合計 + 同時解.一点の接線の乗数の増分(相手の番号) * 自分.勾配().交差の寄与(接線の行.勾配());
            }
        }
        合計
    }
}
