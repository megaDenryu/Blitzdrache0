//! 解けたと見なす許容差が満たすべき条件の試験(判断12・判断13)。担当するのは、擬似逆が固有の向きを捨てた後に
//! 残る残差が、行ごとの許容差の内側に収まることを固定することである。
//! 許容差は誤差の上限ではなく「ここまで残っていれば解けたものとして扱う」という取り決めであるため、その取り決めが
//! 実際に守られていること、つまり捨てたことで生じる残りが取り決めの幅を超えないことを検査で固定する必要がある。
//! 世界の中で平行移動しても成り立つことを見るのは、許容差が座標の大きさで決まるからである。
//! 法線の軸へ動かした配置は収まらない。あちらは要求の精度で解けていない配置であり、型付きの結末で答えることを
//! `translation_tests`が固定する。
//! 保持と滑走の境界が許容差の選び方で動かないことは`scene/tolerance_boundary_tests`が固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 変位};

use super::super::contact_projection_row::一行の二つの符号付き勾配;
use super::system_fixture::{四隅の数, 平行移動して四隅を積んだ連立};

// 材料の法線はy軸、接線変位はx軸である。z軸はそのどちらにも直交する。
fn 世界の変位(x: f32, y: f32, z: f32) -> 変位<ワールド> {
    変位::成分から生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

// 連立の全部の行の勾配・右辺・許容差・増分を、法線の行を先、接線の行を後に並べた4つ組。
fn 平行移動した連立の行を並べる(
    平行移動: 変位<ワールド>
) -> (Vec<一行の二つの符号付き勾配>, Vec<f32>, Vec<f32>, Vec<f32>) {
    let 連立 = 平行移動して四隅を積んだ連立(true, 平行移動);
    let 同時解 = 連立.相補条件を満たす有効集合で同時に解く().定まった解を取り出す();
    let (mut 勾配, mut 右辺, mut 許容差, mut 増分) = (Vec::new(), Vec::new(), Vec::new(), Vec::new());
    for 番号 in 0..四隅の数 {
        let 一行 = 連立.法線の一行を読む(番号).unwrap();
        勾配.push(*一行.勾配());
        右辺.push(一行.連立の右辺().値());
        許容差.push(一行.勾配().解けたと見なす許容差().値());
        増分.push(同時解.一点の法線の乗数の増分(番号).値());
    }
    for 番号 in 0..四隅の数 {
        let 一行 = 連立.接線の一行を読む(番号).unwrap();
        勾配.push(*一行.勾配());
        右辺.push(一行.連立の右辺().値());
        許容差.push(一行.勾配().解けたと見なす許容差().値());
        増分.push(同時解.一点の接線の乗数の増分(番号).値());
    }
    (勾配, 右辺, 許容差, 増分)
}

// 第k行の残差 (J M⁻¹ Jᵀ Δλ)_k − b_k。
fn 第k行の残差(勾配: &[一行の二つの符号付き勾配], 増分: &[f32], 右辺: &[f32], k: usize) -> f32 {
    let 積: f32 = 勾配.iter().zip(増分.iter()).map(|(相手, 増)| 勾配[k].交差の寄与(相手).値() * 増).sum();
    積 - 右辺[k]
}

fn 平行移動した連立の残差が行ごとの許容差に収まることを確かめる(平行移動: 変位<ワールド>, 見出し: &str) {
    let (勾配, 右辺, 許容差, 増分) = 平行移動した連立の行を並べる(平行移動);
    for (k, 行の許容差) in 許容差.iter().enumerate().take(勾配.len()) {
        let 残差 = 第k行の残差(&勾配, &増分, &右辺, k);
        assert!(
            残差.abs() <= *行の許容差,
            "{見出し}で第{k}行の残差{残差}が、その行の解けたと見なす許容差{行の許容差}を超えた"
        );
    }
}

#[test]
fn 固有の向きを捨てた後の残差が行ごとの許容差に収まる() {
    平行移動した連立の残差が行ごとの許容差に収まることを確かめる(世界の変位(0.0, 0.0, 0.0), "原点の付近");
}

#[test]
fn 直交する軸へ遠くまで平行移動しても残差が行ごとの許容差に収まる() {
    平行移動した連立の残差が行ごとの許容差に収まることを確かめる(
        世界の変位(0.0, 0.0, 1.0e6),
        "直交する軸へ100万メートル",
    );
}
