//! 行の右辺を解けたと見なす許容差に掛ける倍率(判断13、Issue #59の数値契約の診断)。本番は常に1倍であり、
//! 1以外を作れるのは試験と計器だけである。
//! この倍率を置くのは、許容差の取り決めが物理の判定(保持と滑走)へ漏れていないことを確かめるには、世界座標を
//! 変えずに許容差だけを振る必要があるためである。世界座標を動かして許容差を変える既存の反証
//! (`scene/tolerance_boundary_tests`)は、同時に座標そのものの表せる細かさも変えるため、2つの原因を分けられない。
//! 掛ける先は2つである。接線の行の右辺 −(C_t − δ) の δ と、擬似逆が右辺の固有の向きを捨てるときに比べる
//! 行ごとの許容差である。法線の隔たりが表現の刻みの内側かどうかの判定には掛けない。あちらは「配置が1ビットも
//! 動かない」という表現の事実であり、解法の取り決めではないためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::メートル;

/// 解けたと見なす許容差に掛ける倍率。
#[derive(Debug, Clone, Copy, PartialEq)]
#[repr(transparent)]
pub struct 解けたと見なす許容差の倍率 {
    比: f32,
}

impl 解けたと見なす許容差の倍率 {
    /// 本番の倍率。1倍を掛ける演算は値を1ビットも変えないため、この倍率を通しても解は変わらない。
    pub fn 既定で生成する() -> Self {
        Self { 比: 1.0 }
    }

    /// 試験と計器が許容差だけを振るための倍率。
    /// 注意: 本番の経路からこの口を呼んではならない。許容差は解法の取り決めであり、場面ごとに変える値ではない。
    #[cfg(test)]
    pub fn 比から生成する(比: f32) -> Self {
        Self { 比 }
    }

    pub fn 許容差へ掛ける(&self, 許容差: メートル) -> メートル {
        許容差 * self.比
    }
}
