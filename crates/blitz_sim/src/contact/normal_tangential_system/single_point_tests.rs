//! 接触点が1つだけの連立の振る舞いの検査(判断13)。担当するのは2つを固定することである。
//! 腕が零の1点では法線の行と接線の行の交差の項が厳密に零になり、接線の増分が旧の逐次の射影と一致すること、
//! そして進めた接線の乗数が「その反復の行の向きへ増分を足した値」であることである。
//! 2つ目が要るのは、接線の乗数がワールドの3成分のベクトルであり、行の向きが反復ごとに接平面の中で回るためである。
//! 4点の並びに依らないことは`order_tests`が、世界位置の平行移動に依らないことは`translation_tests`が固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use std::f32::consts::FRAC_PI_2;

use blitz_math::{ワールド, 変位, 方向};

use super::super::contact_projection_participant::接触の射影に参加する点;
use super::super::static_friction::{
    接線のラグランジュ乗数, 接触点の仮の接線の乗数, 静止摩擦の一回の仮の射影の結果, 静止摩擦の一細分の解の状態, 静止摩擦の連立へ点を入れた結果,
};
use super::single_point_fixture::{一点だけの連立, 接平面で回した静的世界の錨, 重心を錨にした剛体の参加者};
use super::system_fixture::{下向きの接触法線, 法線の乗数, 滑らせる長さ};
use crate::xpbd::ラグランジュ乗数;

// 1点だけの連立を解いた、その反復の行の向きと乗数の増分。
fn 一点の連立を解く(錨b: 接触の射影に参加する点) -> (方向<ワールド>, ラグランジュ乗数) {
    let 連立 = 一点だけの連立(重心を錨にした剛体の参加者(), 錨b, 法線の乗数(1.0));
    let Some(一行) = 連立.接線の一行を読む(0) else {
        panic!("積んだはずの接線の行が連立に無い");
    };
    (一行.接線の向き(), 連立.同時に解く().定まった解を取り出す().一点の接線の乗数の増分(0))
}

#[test]
fn 接触点が一つの集合では逐次の射影と同じ乗数の増分になる() {
    let 参加者 = 重心を錨にした剛体の参加者();
    let 錨a = 接触の射影に参加する点::剛体の局所点から生成する(参加者, 変位::零());
    let 錨b = 接平面で回した静的世界の錨(0.0);
    let 静止摩擦の一回の仮の射影の結果::接線を戻す補正を求めた {
        進めた接線の乗数, ..
    } = 静止摩擦の一細分の解の状態::細分の開始の状態().一回仮に射影する(錨a, 錨b, 下向きの接触法線())
    else {
        panic!("逐次の射影が補正を求めた枝を返していない");
    };
    let (_, 増分) = 一点の連立を解く(錨b);
    let 逐次の大きさ = 進めた接線の乗数.大きさ().値();
    assert!(逐次の大きさ > 0.0, "材料の接線変位が零である");
    assert!(
        (増分.値().abs() - 逐次の大きさ).abs() / 逐次の大きさ < 1.0e-3,
        "1点の集合で同時解{}が逐次の射影{逐次の大きさ}と一致しない",
        増分.値().abs()
    );
}

#[test]
fn 進めた接線の乗数はその反復の行の向きへ増分を足した値である() {
    let x軸: 方向<ワールド> = 方向::生成する(1.0, 0.0, 0.0).unwrap();
    let 既存の乗数 = 接線のラグランジュ乗数::零().向きへの増分を足す(x軸, ラグランジュ乗数::有効逆質量で割った長さから生成する(0.03));
    let 状態 = 静止摩擦の一細分の解の状態::細分の開始の状態().仮の乗数を確定した状態(既存の乗数);
    // z軸の向きへ滑らせた錨を渡すと、行の向きはz軸になる。x軸の既存の乗数はそのまま残る。
    let (向き, 増分) = 一点の連立を解く(接平面で回した静的世界の錨(FRAC_PI_2));
    let 進めた = 接触点の仮の接線の乗数::積んだ行の向きと乗数の増分から決める(
        静止摩擦の連立へ点を入れた結果::一行を積んだ,
        状態,
        Some(向き),
        増分,
    )
    .確定する接線の乗数();
    let 期待 = 既存の乗数.向きへの増分を足す(方向::生成する(0.0, 0.0, 1.0).unwrap(), 増分);
    assert!(
        (進めた.大きさ().値() - 期待.大きさ().値()).abs() < 1.0e-6,
        "行の向きへ増分を足した値になっていない: {進めた:?} と {期待:?}"
    );
    assert!(
        (進めた.大きさ().値() - (0.03 * 0.03 + 滑らせる長さ * 滑らせる長さ).sqrt()).abs() < 1.0e-4,
        "x軸の既存の乗数とz軸の増分が直交して合成されていない: {進めた:?}"
    );
}
