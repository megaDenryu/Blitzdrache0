//! 単精度の本番の連立が定めた解の、数値解法の内側の内訳(Issue #59の第4段階の許容差依存の診断。試験と計器の専用)。
//! 倍精度の`倍精度の解の内訳`と同じ形で、勝った有効集合の抜き出しをもう一度組み、固有の向きごとの固有値・右辺の射影
//! β_k・許容差の積み上がり δ_k・捨てた理由と、行ごとの残差・許容差の内側として捨てた右辺・行の許容差を読む。
//! 向きごとには、本番の規則を同じ配置へ当てた答えと、その向きだけを解いた Jᵀ Δλ が剛体へ入れる並進と回転も持つ。
//! 前者が要るのは、本番の代わりに置く規則を当てた求解でも本番の側の採否を同じ配置で読むためである。
//! 後者が要るのは、向きを解いた結果が箱を滑らせるのか回すのかを、乗数の増分でなく剛体の自由度の側で読むためである。
//! 行ごとの乗数の増分と法線の行の数も持つ。どの行の乗数が受理の倍率で変わったかを綴る計器(Issue #103の段階A)が、
//! 行の番号を法線の行と接線の行へ分けて読むためである。
//! 行ごとの許容差は2つの由来を並べて持つ。粗い位置の刻みから導いた本番の δ_i と、衝突の問い合わせの基準原点に相対な
//! 座標から導いた δ_i(候補(ζ)の式)であり、同じ求解で2つがどれだけ離れるかを綴る計器(Issue #103の段階A4)が読む。
//! 抜き出しを組み直すのは、走査が候補ごとに抜き出しを捨てる工程であり、勝った1つを持ち帰らないためである。
//! 本番の求解と同じ口(`抜き出す`・`解く`・`第k番の向きを捨てた理由`)だけを呼び、判定を1つも書き写さない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

