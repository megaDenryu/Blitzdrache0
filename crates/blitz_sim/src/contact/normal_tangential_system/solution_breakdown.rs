use super::active_set::法線と接線の連立の有効集合;
use super::direction_generalized_correction::剛体の一般化自由度へ入る補正の大きさ;
use super::reduced_system::有効な行だけを抜き出した連立;
use super::system::接触点集合の法線と接線の連立;

/// 擬似逆が扱った固有の向き1つの内訳(単精度)。
pub(in crate::contact) struct 単精度の固有の向きの内訳 {
    pub(in crate::contact) 固有値: f32,
    pub(in crate::contact) 右辺の射影: f32,
    pub(in crate::contact) 許容差の射影: f32,
    pub(in crate::contact) 受理の許容差の射影: f32, // 受理の判定が比べる側の δ_k。候補(α)では擬似逆へ渡す許容差が零であり、上と値が違う
    pub(in crate::contact) 基準原点に相対な座標から導く許容差の射影: f32, // 候補(ζ)の式で数えた δ_i を同じ向きへ積み上げた δ_k。本番の軌道の上で候補(θ')の採否を読む計器が比べる
    pub(in crate::contact) 捨てた理由: 擬似逆が固有の向きを捨てた理由,    // この求解が実際に当てた規則の答えである
    pub(in crate::contact) 本番の判定が捨てるか: bool, // 同じ配置へ本番の規則(|β_k| ≤ δ_k)を当てた答え。枝を当てた求解でも本番の側を読めるように別に持つ
    pub(in crate::contact) 剛体へ入る補正: 剛体の一般化自由度へ入る補正の大きさ, // その向きだけを解いた Jᵀ Δλ が剛体へ入れる並進と回転
}

/// 単精度の本番の連立が定めた解の、数値解法の内側の内訳。
pub(in crate::contact) struct 単精度の解の内訳 {
    pub(in crate::contact) 有効集合: 法線と接線の連立の有効集合,
    pub(in crate::contact) 法線の行の数: usize, // 行の並びは法線が先で接線が後であり、この数が2つの境目である
    pub(in crate::contact) 行ごとの乗数の増分: Vec<f32>,
    pub(in crate::contact) 行ごとの残差: Vec<f32>,
    pub(in crate::contact) 行ごとの許容差の内側として捨てた右辺: Vec<f32>,
    pub(in crate::contact) 行ごとの解けたと見なす許容差: Vec<f32>,
    pub(in crate::contact) 行ごとの基準原点に相対な座標から導く許容差: Vec<f32>, // 候補(ζ)の式で数えた同じ行の δ_i。2つの由来を対で綴る計器が読む
    pub(in crate::contact) 固有の向きごと: Vec<単精度の固有の向きの内訳>,
    pub(in crate::contact) 偽の固有値の下限: f32, // 擬似逆が偽の固有値と見なした下限。固有値がこの下限のどれだけ上に居るかを数える計器が読む
    pub(in crate::contact) 最大の固有値: f32,     // λ_max。固有値を割って相対値の分布を数える計器が読む
    pub(in crate::contact) 右辺の大きさ: f32,     // ‖b‖。増分を場面をまたいで比べる正規化の分母を作る計器が読む
}

impl 接触点集合の法線と接線の連立 {
    /// 相補条件を満たす有効集合が定まったなら、その有効集合で抜き出しを組み直して内訳を読む。定まらなければ無しである。
    /// 走査の勝者を選ぶのは本番と同じ`点の数の多い階層から順に候補を探す`であり、この口は結果を1ビットも変えない。
    pub(in crate::contact) fn 定まった解の内訳を読む(&self) -> Option<単精度の解の内訳> {
        let (候補, _) = self.点の数の多い階層から順に候補を探す();
        Some(単精度の解の内訳::連立と有効集合から読む(self, 候補?.有効集合()))
    }
}

impl 単精度の解の内訳 {
    /// 有効集合へ入れてよい全部の点を有効にした連立の内訳。解が定まらなかった細分で、どの固有の向きが捨てられ、
    /// どの行の残差が許容差を超えたかを読むための口である。走査の結果には関わらない。
    pub(in crate::contact) fn 全点の有効集合から読む(連立: &接触点集合の法線と接線の連立) -> Self {
        Self::連立と有効集合から読む(連立, 連立.有効集合へ入れてよい点の集合())
    }

    fn 連立と有効集合から読む(
        連立: &接触点集合の法線と接線の連立, 有効集合: 法線と接線の連立の有効集合
    ) -> Self {
        let 抜き出した = 有効な行だけを抜き出した連立::抜き出す(連立, &有効集合);
        let 解 = 抜き出した.解く();
        let 行の数 = 抜き出した.並び.行の数();
        let 分解 = 対称な連立の固有分解::分解する(&抜き出した.対称行列, 行の数);
        let 偽の固有値の下限 = 抜き出した.擬似逆が偽の固有値と見なす下限(&分解);
        let 固有の向きごと = (0..行の数)
            .map(|k| 単精度の固有の向きの内訳 {
                固有値: 分解.第k番の固有値(k),
                右辺の射影: 分解.第k番の向きへの射影(k, &抜き出した.定数項),
                許容差の射影: 分解.第k番の向きへの許容差の射影(k, 抜き出した.擬似逆が比べる行ごとの許容差()),
                受理の許容差の射影: 分解.第k番の向きへの許容差の射影(k, &抜き出した.行ごとの解けたと見なす許容差),
                基準原点に相対な座標から導く許容差の射影: 分解
                    .第k番の向きへの許容差の射影(k, &抜き出した.行ごとの基準原点に相対な座標から導く許容差),
                捨てた理由: 抜き出した.第k番の向きを捨てた理由(&分解, k, 偽の固有値の下限),
                本番の判定が捨てるか: 分解.第k番の向きを捨てた理由(
                    k,
                    &抜き出した.定数項,
                    &抜き出した.行ごとの解けたと見なす許容差,
                    偽の固有値の下限,
                ) == 擬似逆が固有の向きを捨てた理由::右辺が許容差の内側,
                剛体へ入る補正: 抜き出した.第k番の向きが剛体へ入れる補正(連立, &有効集合, &分解, k),
            })
            .collect();
        Self {
            有効集合,
            法線の行の数: 抜き出した.並び.法線の行の数(),
            行ごとの乗数の増分: 解.増分()[..行の数].to_vec(),
            行ごとの残差: (0..行の数).map(|k| 抜き出した.第k行の残差(&解, k)).collect(),
            行ごとの許容差の内側として捨てた右辺: (0..行の数).map(|k| 解.第k行の許容差の内側として捨てた右辺(k)).collect(),
            行ごとの解けたと見なす許容差: 抜き出した.行ごとの解けたと見なす許容差[..行の数].to_vec(),
            行ごとの基準原点に相対な座標から導く許容差: 抜き出した.行ごとの基準原点に相対な座標から導く許容差[..行の数].to_vec(),
            固有の向きごと,
            偽の固有値の下限,
            最大の固有値: 分解.固有値の最大(),
            右辺の大きさ: 抜き出した.定数項[..行の数].iter().map(|値| 値 * 値).sum::<f32>().sqrt(),
        }
    }

    /// 右辺をいちばん硬い向き(固有値が最大の向き)で解いたときに要る増分 ‖b‖ ÷ λ_max。
    /// 向きごとの増分を場面をまたいで比べるための正規化の分母である。右辺が零でない限り零にならない。
    pub(in crate::contact) fn 右辺をいちばん硬い向きで解いたときの増分(&self) -> f32 {
        if self.最大の固有値 > 0.0 {
            self.右辺の大きさ / self.最大の固有値
        } else {
            0.0
        }
    }

    /// 指定の理由で扱われた固有の向きの数。
    pub(in crate::contact) fn 捨てた向きの数(&self, 理由: 擬似逆が固有の向きを捨てた理由) -> usize {
        self.固有の向きごと.iter().filter(|向き| 向き.捨てた理由 == 理由).count()
    }

    /// 勝った有効集合を第k番のビットが第k番の接触点として綴った文字列。ビット並びを生の数へ剥がすのはこの表示だけである。
    pub(in crate::contact) fn 有効集合の綴り(&self) -> String {
        format!("{:#010b}", self.有効集合.ビット並び())
    }

    /// 行ごとの残差の絶対値の最大。
    pub(in crate::contact) fn 行ごとの残差の最大(&self) -> f32 {
        self.行ごとの残差.iter().map(|残差| 残差.abs()).fold(0.0, f32::max)
    }
}
