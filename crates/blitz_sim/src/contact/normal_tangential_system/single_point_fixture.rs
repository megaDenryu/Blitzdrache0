//! 重心そのものに接触点と錨を置いた1点だけの連立を組む材料(判断13)。腕を零にすると一般化逆質量が逆質量1に等しくなり、
//! 法線の行と接線の行の交差の項が厳密に零になる。接線の増分が旧の逐次の射影と一致することを手計算で追える。
//! 四隅の材料(`system_fixture`)から分けているのは、あちらが腕を持たせて交差の項を効かせる材料だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::変位;

use super::super::contact_projection_row::接触の射影に参加する点;
use super::super::contact_test_fixtures::{世界の位置を作る, 動的な参加者を作る};
use super::super::non_penetration::非貫通の接触点集合の一行;
use super::system::接触点集合の法線と接線の連立;
use super::system_fixture::{
    下向きの接触法線, 接線の一行を積む, 法線の乗数を積んだ解の状態, 滑らせる長さ, 試験の一刻みの係数
};
use crate::rigid_body::{姿勢, 配置};
use crate::rigid_xpbd::姿勢自由度の参加者;

/// 重心を接触点と錨にした剛体の参加者。腕が零であるため一般化逆質量は逆質量1に等しい。
pub(super) fn 重心を錨にした剛体の参加者() -> 姿勢自由度の参加者 {
    動的な参加者を作る(配置::生成する(世界の位置を作る(0.0, 0.0, 0.0), 姿勢::恒等()), 1.0, 1.0)
}

/// 接平面(x-z)の中で指定の角の向きへ、滑らせる長さだけ離れた静的世界の錨。
pub(super) fn 接平面で回した静的世界の錨(角: f32) -> 接触の射影に参加する点 {
    let (正弦, 余弦) = 角.sin_cos();
    接触の射影に参加する点::静的世界の固定点から生成する(世界の位置を作る(滑らせる長さ * 余弦, 0.0, 滑らせる長さ * 正弦))
}

/// 重心そのものに接触点と錨を置いた1点だけの連立。腕が零であるため法線と接線の交差の項は厳密に零である。
pub(super) fn 一点だけの連立(
    参加者: 姿勢自由度の参加者,
    錨b: 接触の射影に参加する点,
    法線の乗数の値: f32,
) -> 接触点集合の法線と接線の連立 {
    let 重心の点 = 接触の射影に参加する点::剛体の局所点から生成する(参加者, 変位::零());
    let 静的な接触点 = 接触の射影に参加する点::静的世界の固定点から生成する(参加者.配置().重心の位置());
    let mut 連立 = 接触点集合の法線と接線の連立::点の数から空で始める(1);
    連立.法線の一行を積む(
        0,
        非貫通の接触点集合の一行::生成する(
            重心の点,
            静的な接触点,
            下向きの接触法線(),
            法線の乗数を積んだ解の状態(法線の乗数の値),
            試験の一刻みの係数(),
        ),
    );
    接線の一行を積む(&mut 連立, 0, 重心の点, 錨b);
    連立
}
