//! 1回の混合連立の求解について、固有の向きを偽の固有値の下限からの隔たりで仕分けた分布(Issue #103の段階A2の
//! 計測3。試験と計器の専用)。解の内訳(`solution_breakdown`)から分けているのは、あちらが行と向きの量をそのまま
//! 並べて持つ型であり、こちらがその並びを「下限のすぐ上に居る向きが何本あり、それを解いたときの増分がどれだけか」
//! の2つの数へ畳む工程だからである。
//!
//! この分布が要るのは、候補(α)(擬似逆の右辺の判定を当てず、偽の固有値でない向きを全部解く枝)の事故の実在を測る
//! ためである。固有値が下限のすぐ上に居る向きを解くと、増分は |β_k| ÷ λ_k であり、λ_k が小さいほど桁で膨れる。
//! 正則化を退けた理由の事故は、真の増分1.5e-5に対して5.2e-3の増分が向かい合う2行へ現れたことであった。
//! 「すぐ上」の範囲を下限の1倍から100倍と読むのは、段階Aの実測で捨てられた向きの固有値が下限の7桁上に居り、
//! 2桁の帯に何本居るかがその2つの群を分ける問いだからである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::solution_breakdown::単精度の解の内訳;

// 「偽の固有値の下限のすぐ上」と読む帯の上端。下限の何倍までをこの帯に数えるか。
const 下限のすぐ上と読む倍率の上端: f32 = 100.0;

/// 1回の求解の固有の向きを、偽の固有値の下限との比で仕分けた分布。
pub(in crate::contact) struct 偽の固有値の下限に対する固有の向きの分布 {
    行の数: usize,
    偽の固有値の下限: f32,
    下限のすぐ上に居る向きの本数: usize,
    下限のすぐ上に居る向きを解いたときの増分の絶対値の最大: f32,
    偽の固有値でない向きを解いたときの増分の絶対値の最大: f32,
}

impl 偽の固有値の下限に対する固有の向きの分布 {
    /// 解の内訳から分布を読む。増分は、その向きを捨てずに解いたときに解へ入る量 |β_k| ÷ λ_k である。
    pub(in crate::contact) fn 内訳から読む(内訳: &単精度の解の内訳) -> Self {
        let 下限 = 内訳.偽の固有値の下限;
        let mut 分布 = Self {
            行の数: 内訳.固有の向きごと.len(),
            偽の固有値の下限: 下限,
            下限のすぐ上に居る向きの本数: 0,
            下限のすぐ上に居る向きを解いたときの増分の絶対値の最大: 0.0,
            偽の固有値でない向きを解いたときの増分の絶対値の最大: 0.0,
        };
        for 向き in &内訳.固有の向きごと {
            if 向き.固有値 <= 下限 {
                continue;
            }
            let 増分 = (向き.右辺の射影 / 向き.固有値).abs();
            分布.偽の固有値でない向きを解いたときの増分の絶対値の最大 = 分布.偽の固有値でない向きを解いたときの増分の絶対値の最大.max(増分);
            if 向き.固有値 <= 下限 * 下限のすぐ上と読む倍率の上端 {
                分布.下限のすぐ上に居る向きの本数 += 1;
                分布.下限のすぐ上に居る向きを解いたときの増分の絶対値の最大 = 分布.下限のすぐ上に居る向きを解いたときの増分の絶対値の最大.max(増分);
            }
        }
        分布
    }

    pub(in crate::contact) fn 下限のすぐ上に居る向きの本数(&self) -> usize {
        self.下限のすぐ上に居る向きの本数
    }

    /// 下限のすぐ上に居る向きを捨てずに解いたときの増分 |β_k| ÷ λ_k の絶対値の最大。
    pub(in crate::contact) fn 下限のすぐ上に居る向きの増分の最大(&self) -> f32 {
        self.下限のすぐ上に居る向きを解いたときの増分の絶対値の最大
    }

    /// 偽の固有値でない向きを全部解いたときの増分 |β_k| ÷ λ_k の絶対値の最大(候補(α)が作る増分の上限)。
    pub(in crate::contact) fn 真の向きの増分の最大(&self) -> f32 {
        self.偽の固有値でない向きを解いたときの増分の絶対値の最大
    }

    /// 表へ綴る形。
    pub(in crate::contact) fn 綴り(&self) -> String {
        format!(
            "行数={} 偽の固有値の下限={:.3e} 下限の1〜{}倍に居る向き={}本(増分の最大={:.4e}) 全部の真の向きの増分の最大={:.4e}",
            self.行の数,
            self.偽の固有値の下限,
            下限のすぐ上と読む倍率の上端,
            self.下限のすぐ上に居る向きの本数,
            self.下限のすぐ上に居る向きを解いたときの増分の絶対値の最大,
            self.偽の固有値でない向きを解いたときの増分の絶対値の最大
        )
    }
}
