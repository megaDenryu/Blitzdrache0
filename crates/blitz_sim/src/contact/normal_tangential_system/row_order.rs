//! 有効集合に絞ったときに、連立の何番目の行がどの接触点のどちらの拘束かを持つ並び(判断12・判断13)。
//! 法線の行を先に並べ、接線の行を後に並べる。並びを固定するのは、同じ入力から同じ行列と同じ解が出るためである。
//! 抜き出しの型(`reduced_system`)から分けているのは、こちらが番号の対応だけを持ち、あちらが行列と定数項という
//! 数値を持つからである。番号の対応は有効集合の組み替えのたびに作り直され、行列はそのたびに組み直される。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_collision::contact_set::接触点の上限;

use super::active_set::法線と接線の連立の有効集合;
use super::system::接触点集合の法線と接線の連立;

/// 抜き出した連立の1行が、どの接触点のどちらの拘束から来たか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 抜き出した行の持ち主 {
    /// その接触点の法線の隔たりを動かさない行である。
    法線の行を持つ点(usize),
    /// その接触点の錨の接線変位を零へ戻す行である。
    接線の行を持つ点(usize),
}

/// 有効集合に絞った行の並び。
pub(super) struct 抜き出した行の並び {
    法線の行のもとの点の番号: [usize; 接触点の上限],
    法線の行の数: usize,
    接線の行のもとの点の番号: [usize; 接触点の上限],
    接線の行の数: usize,
}

impl 抜き出した行の並び {
    /// 有効な点の法線の行を番号の昇順に並べ、その後ろへ同じ点の接線の行を番号の昇順に並べる。
    pub(super) fn 有効集合から組む(
        連立: &接触点集合の法線と接線の連立, 有効集合: &法線と接線の連立の有効集合
    ) -> Self {
        let mut 並び = Self {
            法線の行のもとの点の番号: [0; 接触点の上限],
            法線の行の数: 0,
            接線の行のもとの点の番号: [0; 接触点の上限],
            接線の行の数: 0,
        };
        for 点の番号 in (0..連立.点の数()).filter(|番号| 有効集合.有効か(*番号)) {
            if 連立.法線の一行を読む(点の番号).is_some() {
                並び.法線の行のもとの点の番号[並び.法線の行の数] = 点の番号;
                並び.法線の行の数 += 1;
            }
            if 連立.接線の一行を読む(点の番号).is_some() {
                並び.接線の行のもとの点の番号[並び.接線の行の数] = 点の番号;
                並び.接線の行の数 += 1;
            }
        }
        並び
    }

    pub(super) fn 行の数(&self) -> usize {
        self.法線の行の数 + self.接線の行の数
    }

    pub(super) fn 法線の行の数(&self) -> usize {
        self.法線の行の数
    }

    pub(super) fn 接線の行の数(&self) -> usize {
        self.接線の行の数
    }

    pub(super) fn 法線の行のもとの点の番号(&self, 法線の行の番号: usize) -> usize {
        self.法線の行のもとの点の番号[法線の行の番号]
    }

    pub(super) fn 接線の行のもとの点の番号(&self, 接線の行の番号: usize) -> usize {
        self.接線の行のもとの点の番号[接線の行の番号]
    }

    /// 抜き出した連立の第k行の持ち主。前提: k は行の数より小さい。
    pub(super) fn 第k行の持ち主(&self, k: usize) -> 抜き出した行の持ち主 {
        if k < self.法線の行の数 {
            抜き出した行の持ち主::法線の行を持つ点(self.法線の行のもとの点の番号[k])
        } else {
            抜き出した行の持ち主::接線の行を持つ点(self.接線の行のもとの点の番号[k - self.法線の行の数])
        }
    }
}
