//! 接触点集合の法線と接線を同じ行列で同時に解いた結果(判断12・判断13)。点ごとの法線の乗数の増分・接線の乗数の
//! 増分・その点の法線の行が有効かの3つを持つ。
//! 連立の型から分けているのは、こちらが解いた後に凍る値であり、連立が行を積むあいだ書き換わる状態を所有するからである。
//! 法線の行が有効かを結果が持つのは、外れた点の接線の乗数を呼び出し側が零へ解放する必要があるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_collision::contact_set::接触点の上限;

use crate::xpbd::ラグランジュ乗数;

/// 接触点集合1つの法線と接線を同時に解いた結果。並びは接触点集合の中の点の番号と同じである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触点集合の法線と接線の同時解 {
    法線の乗数の増分: [ラグランジュ乗数; 接触点の上限],
    接線の乗数の増分: [ラグランジュ乗数; 接触点の上限],
    法線の行が有効か: [bool; 接触点の上限],
}

impl 接触点集合の法線と接線の同時解 {
    /// 1点も入っていない結果。抜き出した連立が点ごとに書き込んで組み上げる。
    pub(super) fn 空() -> Self {
        Self {
            法線の乗数の増分: [ラグランジュ乗数::零(); 接触点の上限],
            接線の乗数の増分: [ラグランジュ乗数::零(); 接触点の上限],
            法線の行が有効か: [false; 接触点の上限],
        }
    }

    pub(super) fn 一点の解を書き込む(
        &mut self,
        点の番号: usize,
        法線の乗数の増分: ラグランジュ乗数,
        接線の乗数の増分: ラグランジュ乗数,
        法線の行が有効か: bool,
    ) {
        self.法線の乗数の増分[点の番号] = 法線の乗数の増分;
        self.接線の乗数の増分[点の番号] = 接線の乗数の増分;
        self.法線の行が有効か[点の番号] = 法線の行が有効か;
    }

    /// 指定の点の法線の乗数の増分 Δλ_n。有効集合から外れた点は乗数を零へ解放する値である。
    pub fn 一点の法線の乗数の増分(&self, 点の番号: usize) -> ラグランジュ乗数 {
        self.法線の乗数の増分[点の番号]
    }

    /// 指定の点の接線の乗数の増分 Δs。連立へ入らなかった点は零である。
    pub fn 一点の接線の乗数の増分(&self, 点の番号: usize) -> ラグランジュ乗数 {
        self.接線の乗数の増分[点の番号]
    }

    /// 指定の点の法線の行が有効集合に残ったか。偽の点は接線の乗数を零へ解放する。
    pub fn 一点の法線の行が有効か(&self, 点の番号: usize) -> bool {
        self.法線の行が有効か[点の番号]
    }
}
