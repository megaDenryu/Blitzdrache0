//! 無作為に散らした法線と接線の連立を次々に組む生成元(判断12・判断13)。階層の走査と全走査の一致を突き合わせる
//! 反証が、点の数と点の食い込み方を広く振った材料を読むために使う。
//! 四隅の材料(`system_fixture`)と別に置くのは、あちらが面と面の接触という決まった配置を固定する材料であり、
//! こちらが決着の順が働く退化と働かない配置の両方を数多く出すための材料だからである。
//! 擬似乱数を保持して自分のメソッドで進めるのは、乱数の並びを進める副作用が自由関数の連鎖を流れないようにする
//! ためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 位置, 変位};

use super::super::contact_projection_row::接触の射影に参加する点;
use super::super::contact_test_fixtures::{世界の位置を作る, 動的な参加者を作る, 局所の変位を作る};
use super::super::non_penetration::非貫通の接触点集合の一行;
use super::pseudo_random_fixture::決まった種から進む擬似乱数;
use super::system::接触点集合の法線と接線の連立;
use super::system_fixture::{
    下向きの接触法線, 接線の一行を積む, 法線の乗数を積んだ解の状態, 試験の一刻みの係数
};
use crate::rigid_body::{姿勢, 配置};
use crate::rigid_xpbd::姿勢自由度の参加者;

// 接触点を散らす底面の広がりであるメートル。
const 底面の半分の長さ: f32 = 0.5;

pub(super) struct 無作為の法線と接線の連立の生成元 {
    乱数: 決まった種から進む擬似乱数,
}

impl 無作為の法線と接線の連立の生成元 {
    pub(super) fn 種から始める(種: u64) -> Self {
        Self {
            乱数: 決まった種から進む擬似乱数::種から始める(種),
        }
    }

    /// 指定の点の数の連立を1つ作る。余白の内側の点を混ぜると、隔たりが正で生成された点が3点に1点の割合で入る。
    pub(super) fn 次の連立を作る(
        &mut self, 点の数: usize, 余白の内側の点を混ぜるか: bool
    ) -> 接触点集合の法線と接線の連立 {
        let 重心 = 配置::生成する(世界の位置を作る(0.0, 0.0, 0.0), 姿勢::恒等());
        let 参加者 = 動的な参加者を作る(重心, self.乱数.範囲の中の単精度の値(0.5, 2.0), self.乱数.範囲の中の単精度の値(0.3, 1.5));
        let mut 連立 = 接触点集合の法線と接線の連立::点の数から空で始める(点の数);
        for 点の番号 in 0..点の数 {
            let 余白の内側か = 余白の内側の点を混ぜるか && 点の番号 % 3 == 0;
            self.一点の二つの行を積む(&mut 連立, 点の番号, 参加者, 余白の内側か);
        }
        連立
    }

    // 1点ぶんの法線の行と接線の行を積む。余白の内側の点は隔たりが正であり、それ以外は食い込んでいる。
    fn 一点の二つの行を積む(
        &mut self,
        連立: &mut 接触点集合の法線と接線の連立,
        点の番号: usize,
        参加者: 姿勢自由度の参加者,
        余白の内側か: bool,
    ) {
        let 隅 = 局所の変位を作る(
            self.乱数.範囲の中の単精度の値(-底面の半分の長さ, 底面の半分の長さ),
            -底面の半分の長さ,
            self.乱数.範囲の中の単精度の値(-底面の半分の長さ, 底面の半分の長さ),
        );
        let 隅の世界位置: 位置<ワールド> = 位置::生成する(隅.x(), 隅.y(), 隅.z());
        let 隔たり = if 余白の内側か {
            self.乱数.範囲の中の単精度の値(1.0e-5, 1.2e-4)
        } else {
            -self.乱数.範囲の中の単精度の値(1.0e-5, 1.5e-3)
        };
        let 剛体の点 = 接触の射影に参加する点::剛体の局所点から生成する(参加者, 隅);
        let 静的な接触点 =
            接触の射影に参加する点::静的世界の固定点から生成する(隅の世界位置.変位を足す(鉛直の変位(-隔たり)));
        連立.法線の一行を積む(
            点の番号,
            非貫通の接触点集合の一行::生成する(
                剛体の点,
                静的な接触点,
                下向きの接触法線(),
                法線の乗数を積んだ解の状態(self.乱数.範囲の中の単精度の値(0.0, 0.08)),
                試験の一刻みの係数(),
            ),
        );
        let 錨b = 接触の射影に参加する点::静的世界の固定点から生成する(隅の世界位置.変位を足す(接平面の変位(
            self.乱数.範囲の中の単精度の値(0.003, 0.02),
            self.乱数.範囲の中の単精度の値(-0.02, 0.02),
        )));
        接線の一行を積む(連立, 点の番号, 剛体の点, 錨b);
    }
}

fn 鉛直の変位(長さ: f32) -> 変位<ワールド> {
    変位::成分から生成する(メートル::生成する(0.0), メートル::生成する(長さ), メートル::生成する(0.0))
}

fn 接平面の変位(x: f32, z: f32) -> 変位<ワールド> {
    変位::成分から生成する(メートル::生成する(x), メートル::生成する(0.0), メートル::生成する(z))
}
