//! 有効集合に絞った抜き出しが連立方程式から読む口(判断12・判断13)。行の勾配・右辺・対角へ足す刻み依存量と、有効集合から
//! 外した点の法線の乗数を零へ解放する増分と、その解放が有効な行の右辺を動かす長さを答える。
//! 連立方程式の定義(`system.rs`)から分けているのは、呼ぶのが抜き出しの工程(`reduced_system`)と相補条件の判定だけであり、
//! 触れるのが点ごとの2つの行を読むことだけだからである。行を積む局面はこの口を1度も読まない。
//! `system.rs` の子モジュールに置くのは、連立方程式の私有のフィールドを読む必要があるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::メートル;

use super::super::super::contact_projection_row::一行の二つの符号付き勾配;
use super::super::active_set::法線と接線の連立方程式の有効集合;
use super::super::row_order::抜き出した行の持ち主;
use super::接触点集合の法線と接線の連立方程式;
use crate::xpbd::ラグランジュ乗数;

impl 接触点集合の法線と接線の連立方程式 {
    /// 有効集合から外した点の法線の乗数を零へ解放する増分 −λ_n。法線の行を持たない点は零である。
    pub(in crate::contact::normal_tangential_system) fn 外した点の法線の乗数を解放する増分(
        &self,
        点の番号: usize,
    ) -> ラグランジュ乗数 {
        match self.点ごとの法線の行[点の番号] {
            Some(法線の行) => ラグランジュ乗数::零() - 法線の行.法線のラグランジュ乗数(),
            None => ラグランジュ乗数::零(),
        }
    }

    /// 外した点の解放の増分が、渡した行の右辺の量を動かす長さ Σ_{j∉A} W_ij Δλ_j。抜き出しがこれを右辺から引く。
    pub(in crate::contact::normal_tangential_system) fn 外した点の解放が動かす長さ(
        &self,
        行の勾配: &一行の二つの符号付き勾配,
        有効集合: &法線と接線の連立方程式の有効集合,
    ) -> メートル {
        let mut 合計 = メートル::生成する(0.0);
        for 点の番号 in (0..self.点の数()).filter(|番号| !有効集合.有効か(*番号)) {
            if let Some(法線の行) = self.点ごとの法線の行[点の番号] {
                合計 = 合計 + self.外した点の法線の乗数を解放する増分(点の番号) * 行の勾配.交差の寄与(法線の行.勾配());
            }
        }
        合計
    }

    pub(in crate::contact::normal_tangential_system) fn 持ち主の行の勾配(
        &self,
        持ち主: 抜き出した行の持ち主,
    ) -> Option<一行の二つの符号付き勾配> {
        match 持ち主 {
            抜き出した行の持ち主::法線の行を持つ点(点の番号) => self.点ごとの法線の行[点の番号].map(|一行| *一行.勾配()),
            抜き出した行の持ち主::接線の行を持つ点(点の番号) => self.点ごとの接線の行[点の番号].map(|一行| *一行.勾配()),
        }
    }

    pub(in crate::contact::normal_tangential_system) fn 持ち主の行の右辺(&self, 持ち主: 抜き出した行の持ち主) -> メートル {
        let 零 = メートル::生成する(0.0);
        match 持ち主 {
            抜き出した行の持ち主::法線の行を持つ点(点の番号) => {
                self.点ごとの法線の行[点の番号].map_or(零, |一行| 一行.連立方程式の右辺())
            }
            抜き出した行の持ち主::接線の行を持つ点(点の番号) => {
                self.点ごとの接線の行[点の番号].map_or(零, |一行| 一行.連立方程式の右辺())
            }
        }
    }

    /// 法線の行の対角へ足すコンプライアンスの刻み依存量 α̃。接線の行は硬い位置拘束であるため零である。
    pub(in crate::contact::normal_tangential_system) fn 持ち主の行の対角へ足す刻み依存量(
        &self, 持ち主: 抜き出した行の持ち主
    ) -> f32 {
        match 持ち主 {
            抜き出した行の持ち主::法線の行を持つ点(点の番号) => {
                self.点ごとの法線の行[点の番号].map_or(0.0, |一行| 一行.刻み依存量().値())
            }
            抜き出した行の持ち主::接線の行を持つ点(_) => 0.0,
        }
    }
}
