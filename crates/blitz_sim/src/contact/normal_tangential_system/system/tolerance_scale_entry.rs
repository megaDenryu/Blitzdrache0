//! 解けたと見なす許容差だけを振った連立を組む口(Issue #59の数値契約の診断。試験と計器の専用)。
//! 連立の定義(`system.rs`)から分けているのは、本番の細分の工程がこの口を1度も読まないためである。
//! 本番は倍率を意識せず`点の数から空で始める`だけを読み、そこが既定の1倍を入れる。倍率を指定する引数を
//! 本番の構築の口に並べると、読まない引数を全部の呼び出し側が毎回渡すことになる。
//! `system.rs`の子モジュールに置くのは、連立の私有のフィールドへ書き込む必要があるためである。Rustの可視性は
//! モジュール木で決まり、兄弟のモジュールからは私有のフィールドが見えない。
//! 注意: 1以外の倍率を渡してよいのは数値契約の診断の計器だけである。許容差は解法の取り決めであり、場面ごとに
//! 変える値ではない。1以外の倍率そのものを作る口(`解けたと見なす許容差の倍率::比から生成する`)も試験構成に限る。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_collision::contact_set::接触点の上限;

use super::super::tolerance_scale::解けたと見なす許容差の倍率;
use super::接触点集合の法線と接線の連立;

impl 接触点集合の法線と接線の連立 {
    /// 解けたと見なす許容差だけを振った、1行も積んでいない連立。
    /// 注意: 点の数が接触点の上限を超える集合は衝突数学層の不変条件の破れであり、添字の範囲外として落ちる。
    pub fn 点の数と許容差の倍率から空で始める(点の数: usize, 倍率: 解けたと見なす許容差の倍率) -> Self {
        Self {
            点ごとの法線の行: [None; 接触点の上限],
            点ごとの接線の行: [None; 接触点の上限],
            点の数,
            解けたと見なす許容差の倍率: 倍率,
        }
    }

    /// この連立が行の許容差へ掛ける倍率。抜き出しの後処理だけが読む。
    pub fn 解けたと見なす許容差の倍率(&self) -> 解けたと見なす許容差の倍率 {
        self.解けたと見なす許容差の倍率
    }
}
