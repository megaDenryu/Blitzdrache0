//! 解けたと見なす許容差の適用規則だけを振った連立方程式を組む口(Issue #59の数値契約の診断。試験と計器の専用)。
//! 連立方程式の定義(`system.rs`)から分けているのは、本番の細分の工程がこの口を1度も読まないためである。
//! 本番は適用規則を意識せず`点の数から空で始める`だけを読み、そこが本番と同じ適用規則を入れる。適用規則を指定する引数を
//! 本番の構築の口に並べると、読まない引数を全部の呼び出し側が毎回渡すことになる。
//! `system.rs`の子モジュールに置くのは、連立方程式の私有のフィールドへ書き込む必要があるためである。Rustの可視性は
//! モジュール木で決まり、兄弟のモジュールからは私有のフィールドが見えない。
//! 注意: 本番と違う適用規則を渡してよいのは数値契約の診断の計器だけである。許容差は解法の取り決めであり、場面ごとに
//! 変える値ではない。本番と違う適用規則そのものを作る口も試験構成に限る。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_collision::contact_set::接触点の上限;

use super::super::tolerance_application::試験の許容差の適用規則;
use super::接触点集合の法線と接線の連立方程式;

impl 接触点集合の法線と接線の連立方程式 {
    /// 解けたと見なす許容差の適用規則だけを振った、1行も積んでいない連立方程式。
    /// 注意: 点の数が接触点の上限を超える集合は衝突数学層の不変条件の破れであり、添字の範囲外として落ちる。
    pub fn 点の数と試験の許容差の適用規則から空で始める(
        点の数: usize, 適用規則: 試験の許容差の適用規則
    ) -> Self {
        Self {
            点ごとの法線の行: [None; 接触点の上限],
            点ごとの接線の行: [None; 接触点の上限],
            点ごとの積まなかった接線の残差: [None; 接触点の上限],
            点の数,
            試験の許容差の適用規則: 適用規則,
        }
    }

    /// この連立方程式が行の許容差と接線の行の右辺へ当てる指定。抜き出しの後処理だけが読む。
    pub fn 試験の許容差の適用規則(&self) -> 試験の許容差の適用規則 {
        self.試験の許容差の適用規則
    }
}
