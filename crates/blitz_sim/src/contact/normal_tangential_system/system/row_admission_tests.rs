//! 接線の行を連立へ積むかの閾値の反証(判断13の2026-09-12の改訂)。担当するのは、本番の適用規則で C_t が解けたと見なす
//! 許容差 δ の内側(0.5δ)と等号ちょうど(δ)の行を積まず、外側(2δ)の行だけを積むことと、積まなかった点の残差を
//! 連立が受理の判定(A)のために覚えることを固定することである。不等号の向きを壊すと、この試験が先に落ちる。
//! 錨を世界の原点から20メートルの位置に置くのは、原点の付近では座標の表現の刻みがほぼ零になり閾値が読めないためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 変位, 方向};

use super::super::super::contact_projection_row::接触の射影に参加する点;
use super::super::super::contact_test_fixtures::{世界の位置を作る, 動的な参加者を作る};
use super::super::tangential_row::錨の接線変位を零へ戻す一行;
use super::接触点集合の法線と接線の連立;
use crate::rigid_body::{姿勢, 配置};

const 原点からの距離: f32 = 20.0;

// 世界の原点から x 軸の向きへ20メートル離れた点に、剛体の重心の錨と静的世界の錨を重ねて置く。
fn 二つの錨() -> (接触の射影に参加する点, 接触の射影に参加する点) {
    let 配置 = 配置::生成する(世界の位置を作る(原点からの距離, 0.0, 0.0), 姿勢::恒等());
    let 参加者 = 動的な参加者を作る(配置, 1.0, 1.0);
    (
        接触の射影に参加する点::剛体の局所点から生成する(参加者, 変位::零()),
        接触の射影に参加する点::静的世界の固定点から生成する(世界の位置を作る(原点からの距離, 0.0, 0.0)),
    )
}

// 接線変位の長さを δ の比で指定した行。長さは錨の位置と独立に与えられるため、閾値の両側を狙って作れる。
fn 許容差の比の行(比: f32) -> 錨の接線変位を零へ戻す一行 {
    let (錨a, 錨b) = 二つの錨();
    let 向き: 方向<ワールド> = 方向::生成する(0.0, 0.0, 1.0).unwrap();
    let 閾値 = 錨の接線変位を零へ戻す一行::錨と接線変位から生成する(錨a, 錨b, 向き, メートル::生成する(1.0))
        .勾配()
        .解けたと見なす許容差();
    assert!(閾値.値() > 0.0, "閾値が零では不等号の向きを試せない: {閾値:?}");
    錨の接線変位を零へ戻す一行::錨と接線変位から生成する(錨a, 錨b, 向き, 閾値 * 比)
}

#[test]
fn 許容差の内側と等号ちょうどの行は積まず外側の行だけを積む() {
    let 連立 = 接触点集合の法線と接線の連立::点の数から空で始める(1);
    assert!(!連立.接線の行を積むか(&許容差の比の行(0.5)), "許容差の内側の行を積んだ");
    assert!(!連立.接線の行を積むか(&許容差の比の行(1.0)), "許容差と等しい行を積んだ(等号は内側である)");
    assert!(連立.接線の行を積むか(&許容差の比の行(2.0)), "許容差の外側の行を積まなかった");
}

#[test]
fn 積まなかった点の残差を連立が覚える() {
    let mut 連立 = 接触点集合の法線と接線の連立::点の数から空で始める(2);
    let 行 = 許容差の比の行(0.5);
    連立.接線の行を積まなかった点を記す(1, &行);
    assert_eq!(連立.積まなかった点の残差を読む(0), None);
    assert_eq!(連立.積まなかった点の残差を読む(1), Some(行.接線変位と許容差()));
    assert!(行.接線変位と許容差().許容差の内側か());
}
