//! 接線の行を連立方程式へ積むかの判定と、積まなかった点の記録(判断13の2026-09-12の改訂)。連立方程式の定義(`system.rs`)から
//! 分けているのは、触れるフィールドが「積まなかった点の残差」(と試験の構成の適用規則)だけに限られ、行を積む工程だけが
//! 呼ぶ規律を持つためである。C_t がその行の解けたと見なす許容差 δ の内側の行は「すでに数値上満たしている」として積まず、
//! その点の元の接線拘束に対する残差 C_t と閾値 δ を、混合連立方程式の受理の判定(A)のために連立方程式が覚える。
//! 本番の構成は適用規則の型を知らず、閾値の判定を行そのものから読む。試験の構成だけが、対照(旧の形・候補(i))のために
//! 適用規則で判定を差し替える。本番と同じ適用規則なら答えは本番と同じである。
//! `system.rs` の子モジュールに置くのは、連立方程式の私有のフィールドへ書き込む必要があるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::super::acceptance::残差と受理の許容差;
use super::super::tangential_row::錨の接線変位を零へ戻す一行;
use super::接触点集合の法線と接線の連立方程式;

impl 接触点集合の法線と接線の連立方程式 {
    /// この接線の行を連立方程式へ積むか。C_t がその行の解けたと見なす許容差 δ の内側の行は積まない。
    #[cfg(not(test))]
    pub fn 接線の行を積むか(&self, 一行: &錨の接線変位を零へ戻す一行) -> bool {
        !一行.許容差の内側か()
    }

    /// 試験の構成の同じ判定。本番と同じ適用規則なら本番と同じ答えを返し、対照の適用規則だけが全部の行を積む。
    #[cfg(test)]
    pub fn 接線の行を積むか(&self, 一行: &錨の接線変位を零へ戻す一行) -> bool {
        self.試験の許容差の適用規則.接線の行を積むか(一行)
    }

    /// C_t が許容差の内側で行を積まなかった点を記す。受理の判定(A)がこの残差を読む。
    #[cfg(not(test))]
    pub fn 接線の行を積まなかった点を記す(&mut self, 点の番号: usize, 一行: &錨の接線変位を零へ戻す一行) {
        self.点ごとの積まなかった接線の残差[点の番号] = Some(一行.接線変位と許容差());
    }

    /// 試験の構成の同じ記録。閾値の帯の適用規則では閾値 k δ を(A)の許容差として記す(積まない判定と同じ量で受理する)。
    #[cfg(test)]
    pub fn 接線の行を積まなかった点を記す(&mut self, 点の番号: usize, 一行: &錨の接線変位を零へ戻す一行) {
        self.点ごとの積まなかった接線の残差[点の番号] = Some(self.試験の許容差の適用規則.積まなかった点の残差と閾値(一行));
    }

    /// 行を積まなかった点の残差 C_t と閾値 δ。積んだ点と、接線変位が零の点は無しである。
    pub(in crate::contact::normal_tangential_system) fn 積まなかった点の残差を読む(
        &self,
        点の番号: usize,
    ) -> Option<残差と受理の許容差> {
        self.点ごとの積まなかった接線の残差[点の番号]
    }
}
