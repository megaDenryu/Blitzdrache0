//! 連立方程式の固有値を最大の固有値で割った相対値が、どの桁にどれだけ居るかの広がり(Issue #103の段階A3の計測1。
//! 試験と計器の専用)。偽の固有値の下限との比だけを見る`偽の固有値の下限に対する固有の向きの分布`から分けているのは、
//! あちらが「下限のすぐ上に向きが居るか」を1つの帯で数える型であり、こちらが固有値の並び全体の形を読む型だからである。
//!
//! この広がりが要るのは、階数不足の向き(面と面の4点の法線が3自由度しか持たないことから生じる向き)と、物理的に
//! 意味のある向きとのあいだに、相対値でどれだけの隙間が開くかを読むためである。隙間があるなら、そこへ相対比で
//! 閾値を置ける。最も広い隙間を求解ごとに求め、その下端の最大と上端の最小を溜めるのは、閾値が全部の求解で同じ
//! 隙間の中に入る必要があるためである。下端の最大が上端の最小を下回れば、その2つに挟まれた帯が閾値を置ける範囲になる。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::decade_histogram::{最も広い隙間を探す, 桁ごとの度数};
use super::solution_breakdown::単精度の解の内訳;

// 数える桁の本数。第0番は相対値が 1e-8 より小さい向き、第i番は 1e-(9-i) 以上 1e-(8-i) 未満の向きである。
const 数える桁の本数: usize = 9;
const いちばん低い桁の下端の十の冪: i32 = -8;

/// 複数の求解を通した、固有値を最大で割った相対値の広がり。
pub(in crate::contact) struct 固有値を最大で割った相対値の広がり {
    数えた求解の数: usize,
    桁ごとの度数: 桁ごとの度数,
    最も広い隙間の下端の最大: f32,
    最も広い隙間の上端の最小: f32,
    偽の固有値の下限の相対値の最大: f32,
}

impl 固有値を最大で割った相対値の広がり {
    pub(in crate::contact) fn 零から始める() -> Self {
        Self {
            数えた求解の数: 0,
            桁ごとの度数: 桁ごとの度数::範囲から始める(いちばん低い桁の下端の十の冪, 数える桁の本数),
            最も広い隙間の下端の最大: 0.0,
            最も広い隙間の上端の最小: f32::INFINITY,
            偽の固有値の下限の相対値の最大: 0.0,
        }
    }

    /// 1回の求解の固有値を数える。最大の固有値が正でない求解は数えない。
    pub(in crate::contact) fn 一回の求解を数える(&mut self, 内訳: &単精度の解の内訳) {
        let 最大の固有値 = 内訳.最大の固有値;
        if 最大の固有値 <= 0.0 {
            return;
        }
        let mut 相対値 = 相対値を小さい順に並べる(内訳, 最大の固有値);
        self.数えた求解の数 += 1;
        self.偽の固有値の下限の相対値の最大 = self.偽の固有値の下限の相対値の最大.max(内訳.偽の固有値の下限 / 最大の固有値);
        for 値 in &相対値 {
            self.桁ごとの度数.一つ数える(*値);
        }
        相対値.dedup();
        let Some((下端, 上端)) = 最も広い隙間を探す(&相対値) else {
            return;
        };
        self.最も広い隙間の下端の最大 = self.最も広い隙間の下端の最大.max(下端);
        self.最も広い隙間の上端の最小 = self.最も広い隙間の上端の最小.min(上端);
    }

    /// 全部の求解の最も広い隙間が重なっている範囲。重なりが無ければ無しである。
    pub(in crate::contact) fn 閾値を置ける帯(&self) -> Option<(f32, f32)> {
        (self.最も広い隙間の下端の最大 < self.最も広い隙間の上端の最小).then_some((self.最も広い隙間の下端の最大, self.最も広い隙間の上端の最小))
    }

    /// 表へ綴る形。
    pub(in crate::contact) fn 綴り(&self) -> String {
        let 桁 = self.桁ごとの度数.綴り();
        let 帯 = match self.閾値を置ける帯() {
            Some((下端, 上端)) => format!("{下端:.3e}〜{上端:.3e}(桁の幅{:.2})", (上端 / 下端).log10()),
            None => "無し(隙間が重ならない)".to_owned(),
        };
        format!(
            "求解={}件 桁ごとの度数[{桁}] 隙間の下端の最大={:.3e} 隙間の上端の最小={:.3e} 閾値を置ける帯={帯} 偽の固有値の下限の相対値の最大={:.3e}",
            self.数えた求解の数, self.最も広い隙間の下端の最大, self.最も広い隙間の上端の最小, self.偽の固有値の下限の相対値の最大
        )
    }
}

// 正の固有値を最大の固有値で割って小さい順に並べる。零以下の固有値は桁を持たないため外す。
fn 相対値を小さい順に並べる(内訳: &単精度の解の内訳, 最大の固有値: f32) -> Vec<f32> {
    let mut 並び: Vec<f32> = 内訳
        .固有の向きごと
        .iter()
        .filter(|向き| 向き.固有値 > 0.0)
        .map(|向き| 向き.固有値 / 最大の固有値)
        .collect();
    並び.sort_by(f32::total_cmp);
    並び
}
