//! 取りうる部分集合を全部走査して候補を探す、試験専用の正典(判断13)。
//! 本番の経路は階層の走査(`subset_search`)を通る。こちらを残しているのは、階層で打ち切る形が全走査と同じ候補を
//! 返すことを、実装の外側から突き合わせるためである。打ち切りの正しさは「決着の第1の鍵が有効な点の数である」
//! という決着の順(`candidate`)に依っており、決着の順を変えるとこの一致が壊れる。壊れたことを検査で捕まえる
//! ためには、決着の順を読まない基準の実装が要る。
//! 候補が現れた点の数の種類を数える口を持つのは、突き合わせに使う材料が「複数の階層が同時に相補条件を満たす」
//! 退化を実際に含んでいるかを、検査自身が確かめるためである。含んでいなければ、走査の向きを逆にした誤りを
//! その材料は捕まえられない。
//! この工程が本番から呼ばれないことは、`#![cfg(test)]` が機械で保証する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::candidate::相補条件を満たした候補;
use super::system::接触点集合の法線と接線の連立;

impl 接触点集合の法線と接線の連立 {
    /// 有効集合へ入れてよい点の部分集合を1つ残らず解き、決着の順で先に来る1つを返す。
    pub(super) fn 全部の部分集合を走査して候補を探す(&self) -> Option<相補条件を満たした候補> {
        self.相補条件を満たした候補を全部集める()
            .into_iter()
            .reduce(相補条件を満たした候補::先に選ぶ方を採る)
    }

    /// 相補条件を満たす候補が現れた「有効な点の数」の種類の数。2以上なら、階層で打ち切る走査が下の階層を
    /// 実際に捨てている材料である。
    pub(super) fn 相補条件を満たす候補が現れた点の数の種類を数える(&self) -> usize {
        let mut 現れた点の数: Vec<usize> = self
            .相補条件を満たした候補を全部集める()
            .iter()
            .map(|候補| 候補.有効集合().点の数を数える())
            .collect();
        現れた点の数.sort_unstable();
        現れた点の数.dedup();
        現れた点の数.len()
    }

    // 取りうる部分集合を1つ残らず解き、相補条件を満たした候補を集める。枚挙を1箇所へ閉じるため、上の2つの口は
    // どちらもこれを通る。
    fn 相補条件を満たした候補を全部集める(&self) -> Vec<相補条件を満たした候補> {
        let 入れてよい点 = self.有効集合へ入れてよい点の集合();
        let mut 一覧 = Vec::new();
        let mut 部分集合 = 入れてよい点;
        loop {
            if let Some(候補) = self.一つの部分集合を候補にする(部分集合) {
                一覧.push(候補);
            }
            if 部分集合.一点も含まないか() {
                break;
            }
            部分集合 = 部分集合.全体の中で次に小さい部分集合(&入れてよい点);
        }
        一覧
    }
}
