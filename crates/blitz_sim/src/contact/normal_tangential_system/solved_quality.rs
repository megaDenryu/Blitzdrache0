//! 抜き出した連立を解いた行の残差と、その解が作る補正の大きさ(判断12・判断13)。相補条件を満たす候補が複数
//! 残ったときの決着と、要求の精度で解けたかの判定に使う2つの量を持つ。
//! 残差を持つのは、擬似逆が固有の向きを捨てた結果として右辺が残るためである。行ごとの許容差の内側に収まらない
//! 残差を無視して粘着の成功にしてはならない。世界の原点から遠い配置では、法線の行の許容差が座標の表現の刻みまで
//! 粗くなる一方で接線の行の許容差は細かいままであり、接線の行だけが解けていない状態が起こる。
//! 補正の質量の計量のノルム √(Δλᵀ (W + α̃) Δλ) を持つのは、残差が等しい候補が複数あるときに、同じ拘束を
//! より小さい補正で満たす候補を選ぶためである(補正の質量の計量は、その補正が動かす運動エネルギーの計量である)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

/// 抜き出した連立を1つの有効集合で解いた結果の質。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 解いた行の残差と補正の大きさ {
    残差のノルム: f32,             // メートル
    補正の質量の計量のノルム: f32, // メートル ÷ √キログラム
    全部の行の残差が許容差の内側か: bool,
}

impl 解いた行の残差と補正の大きさ {
    pub(super) fn 三つの量から組む(
        残差のノルム: f32, 補正の質量の計量のノルム: f32, 全部の行の残差が許容差の内側か: bool
    ) -> Self {
        Self {
            残差のノルム,
            補正の質量の計量のノルム,
            全部の行の残差が許容差の内側か,
        }
    }

    /// 全部の行の残差が、その行を解けたと見なす許容差の内側に収まったか。偽なら要求の精度で解けていない。
    pub(super) fn 全部の行の残差が許容差の内側か(&self) -> bool {
        self.全部の行の残差が許容差の内側か
    }

    /// 残差のノルムを先に、同じなら補正の質量の計量のノルムを比べる順序。どちらも小さい方を先に選ぶ。
    /// 非数を含みうる比較であるため全順序で比べる(同じ入力から同じ候補が選ばれるためである)。
    pub(super) fn 先に選ぶ順で比べる(&self, 相手: &Self) -> std::cmp::Ordering {
        self.残差のノルム
            .total_cmp(&相手.残差のノルム)
            .then_with(|| self.補正の質量の計量のノルム.total_cmp(&相手.補正の質量の計量のノルム))
    }
}
