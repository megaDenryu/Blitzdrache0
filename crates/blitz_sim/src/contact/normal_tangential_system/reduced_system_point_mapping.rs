//! 擬似逆が解いた行ごとの増分を、接触点ごとの増分へ戻す工程(判断12・判断13)。
//! 抜き出し(`reduced_system`)から分けているのは、あちらが有効集合ごとに行列と右辺を組んで解く工程であり、
//! こちらがその解を行の並びから点の番号へ写し戻す工程だからである。受け取るのは解と連立と有効集合、返すのは
//! 点ごとの法線と接線の増分である。有効集合から外れた点には、法線の乗数を零へ解放する増分を置く。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_collision::contact_set::接触点の上限;

use super::super::symmetric_system::擬似逆で解いた増分と捨てた右辺;
use super::active_set::法線と接線の連立の有効集合;
use super::reduced_system::有効な行だけを抜き出した連立;
use super::solution::接触点集合の法線と接線の同時解;
use super::system::接触点集合の法線と接線の連立;
use crate::xpbd::ラグランジュ乗数;

impl 有効な行だけを抜き出した連立 {
    /// 解いた増分を点ごとの増分へ戻す。外した点の法線の乗数は零へ解放する増分になる。
    pub(super) fn もとの点へ戻す(
        &self,
        解: &擬似逆で解いた増分と捨てた右辺,
        連立: &接触点集合の法線と接線の連立,
        有効集合: &法線と接線の連立の有効集合,
    ) -> 接触点集合の法線と接線の同時解 {
        let 解 = 解.増分();
        let mut 法線の増分 = [ラグランジュ乗数::零(); 接触点の上限];
        let mut 接線の増分 = [ラグランジュ乗数::零(); 接触点の上限];
        for k in 0..self.並び.法線の行の数() {
            法線の増分[self.並び.法線の行のもとの点の番号(k)] = ラグランジュ乗数::有効逆質量で割った長さから生成する(解[k]);
        }
        for k in 0..self.並び.接線の行の数() {
            接線の増分[self.並び.接線の行のもとの点の番号(k)] =
                ラグランジュ乗数::有効逆質量で割った長さから生成する(解[self.並び.法線の行の数() + k]);
        }
        let mut 同時解 = 接触点集合の法線と接線の同時解::空();
        for 点の番号 in 0..連立.点の数() {
            let 有効 = 有効集合.有効か(点の番号);
            let 法線 = if 有効 {
                法線の増分[点の番号]
            } else {
                連立.外した点の法線の乗数を解放する増分(点の番号)
            };
            同時解.一点の解を書き込む(点の番号, 法線, 接線の増分[点の番号], 有効);
        }
        同時解
    }
}
