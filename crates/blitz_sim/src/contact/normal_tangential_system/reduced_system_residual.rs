//! 抜き出した連立を解いた行の残差と補正の大きさを測る工程(判断12・判断13)。
//! 抜き出しの型(`reduced_system`)から局面として分けているのは、あちらが有効集合ごとに1度だけ行列と右辺を組む
//! 工程であるのに対し、こちらがその行列と解を読むだけの測りだからである。触れるのは対称行列・定数項・
//! 行ごとの許容差の3つと、渡された解である。
//! 残差は擬似逆が捨てた固有の向きの分だけ残る。行ごとの許容差と比べて「解けたと見なせるか」をここで決め、
//! 決まらない候補は呼び出し側が表現の精度の不足として扱う。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::メートル;

use super::super::symmetric_system::{擬似逆で解いた増分と捨てた右辺, 法線と接線の連立の行の上限};
use super::acceptance::{残差と受理の許容差, 混合連立の受理の材料};
use super::reduced_system::有効な行だけを抜き出した連立;
use super::row_order::抜き出した行の持ち主;
use super::solved_quality::解いた行の残差と補正の大きさ;
use super::system::接触点集合の法線と接線の連立;

impl 有効な行だけを抜き出した連立 {
    /// 解いた増分の残差 (A Δλ)_k − b_k と、補正の質量の計量のノルム √(Δλᵀ A Δλ) を測る。
    /// 許容差の内側かを見るのは残差の全体ではなく、許容差の内側として捨てた右辺の成分だけである。残差にはこの
    /// 連立の階数では満たせない成分も混ざり、そちらは座標を細かくしても消えない(`pseudo_inverse_solution`)。
    pub(super) fn 解いた行の残差と補正の大きさを測る(
        &self,
        解: &擬似逆で解いた増分と捨てた右辺,
    ) -> 解いた行の残差と補正の大きさ {
        let 増分 = 解.増分();
        let mut 残差の二乗和 = 0.0;
        let mut 補正の二乗 = 0.0;
        let mut 全部の行が許容差の内側 = true;
        for k in 0..self.並び.行の数() {
            let 積 = self.第k行と解の積(増分, k);
            let 残差 = 積 - self.定数項[k];
            残差の二乗和 += 残差 * 残差;
            補正の二乗 += 増分[k] * 積;
            全部の行が許容差の内側 &= 解.第k行の許容差の内側として捨てた右辺(k).abs() <= self.行ごとの解けたと見なす許容差[k];
        }
        解いた行の残差と補正の大きさ::三つの量から組む(残差の二乗和.sqrt(), 補正の二乗.max(0.0).sqrt(), 全部の行が許容差の内側)
    }

    /// 混合連立の受理の判定の材料のうち、この連立から測れる4つ(A・B1・B2・B4)を測る(判断13の2026-09-12の改訂)。
    /// B1 は積んだ接線の行の元の行空間の残差 (A Δλ)_k − b_k の全体であり、階数で満たせない成分も含む。B4 は行ごとの
    /// 捨てた右辺である。B2 は、この材料を測るのが相補条件を満たした候補だけであるため真である。円錐(B3)は呼び出し側が記す。
    pub(super) fn 混合連立の受理の材料を測る(
        &self,
        解: &擬似逆で解いた増分と捨てた右辺,
        連立: &接触点集合の法線と接線の連立,
    ) -> 混合連立の受理の材料 {
        let mut 材料 = 混合連立の受理の材料::空から始める();
        for k in 0..self.並び.行の数() {
            let 許容差 = 受理の判定の許容差(連立, メートル::生成する(self.行ごとの解けたと見なす許容差[k]));
            let 捨てた右辺 = メートル::生成する(解.第k行の許容差の内側として捨てた右辺(k));
            材料.捨てた成分を戻した残差を記す(k, 残差と受理の許容差::残差と許容差から生成する(捨てた右辺, 許容差));
            if let 抜き出した行の持ち主::接線の行を持つ点(点の番号) = self.並び.第k行の持ち主(k) {
                let 残差 = メートル::生成する(self.第k行と解の積(解.増分(), k) - self.定数項[k]);
                材料.積んだ接線の行を記す(点の番号, 残差と受理の許容差::残差と許容差から生成する(残差, 許容差));
            }
        }
        for 点の番号 in 0..連立.点の数() {
            if let Some(残差) = 連立.積まなかった点の残差を読む(点の番号) {
                材料.積まなかった点を記す(点の番号, 残差);
            }
        }
        // 受理の判定(A)の許容差は行を積む閾値の δ そのものであり、倍率は掛けない(閾値と受理の δ を束ねない)。
        材料.相補条件の判定を記す(true);
        材料
    }

    /// 第k行の残差 (A Δλ)_k − b_k。捨てた向きの内訳を綴る計器が行ごとに読む口である。
    #[cfg(test)]
    pub(super) fn 第k行の残差(&self, 解: &擬似逆で解いた増分と捨てた右辺, k: usize) -> f32 {
        self.第k行と解の積(解.増分(), k) - self.定数項[k]
    }

    // 第k行と解の積 (A Δλ)_k。
    fn 第k行と解の積(&self, 解: &[f32; 法線と接線の連立の行の上限], k: usize) -> f32 {
        self.対称行列[k]
            .iter()
            .zip(解.iter())
            .take(self.並び.行の数())
            .map(|(成分, 増分)| 成分 * 増分)
            .sum()
    }
}

// 受理の判定(B1・B4)が比べる許容差。本番は抜き出した行の許容差そのものである。
#[cfg(not(test))]
fn 受理の判定の許容差(_連立: &接触点集合の法線と接線の連立, 許容差: メートル) -> メートル {
    許容差
}

// 試験の構成では、受理の倍率を受理の判定だけへ届かせる当て方のときにここで倍率を掛ける(擬似逆の側で掛けた当て方では掛けない)。
#[cfg(test)]
fn 受理の判定の許容差(連立: &接触点集合の法線と接線の連立, 許容差: メートル) -> メートル {
    連立.試験の許容差の当て方().受理の判定の許容差へ掛ける(許容差)
}
