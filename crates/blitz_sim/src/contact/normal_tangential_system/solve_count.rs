//! 有効集合を探すあいだに連立を解いた回数(判断13)。実際に解いた数と、取りうる部分集合を全部走査したならば
//! 解いたはずの数を対で持つ。
//! 2つを1つの値にするのは、片方だけを見ても費用の主張ができないためである。「階層で打ち切ったから減った」と
//! 言うには、同じ場面で全走査ならば何回だったかが要る。2つは必ず同じ求解のたびに揃って増える。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_collision::contact_set::接触点の上限;

/// 1回の求解、または数え上げた区間の合計についての、連立を解いた回数の対。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 部分集合を解いた回数 {
    階層の走査が解いた数: u64,
    全走査ならば解く数: u64,
}

impl 部分集合を解いた回数 {
    /// 1回の求解の回数。階層の走査が実際に解いた数と、入れてよい点の数から決まる全走査の数から組む。
    /// 注意: 入れてよい点の数が接触点の上限以下であることは衝突数学層の不変条件であり、破れたらここで落とす。
    /// 数え違いを既定値へ倒すと、費用の主張が黙って壊れる。
    pub(super) fn 一回の求解から組む(階層の走査が解いた数: usize, 入れてよい点の数: usize) -> Self {
        assert!(
            入れてよい点の数 <= 接触点の上限,
            "有効集合へ入れてよい点の数が接触点の上限を超えた: {入れてよい点の数}"
        );
        let (Ok(解いた数), Ok(全走査でずらす幅)) = (u64::try_from(階層の走査が解いた数), u32::try_from(入れてよい点の数))
        else {
            panic!("解いた部分集合の数か点の数が数の型へ収まらない: {階層の走査が解いた数} と {入れてよい点の数}");
        };
        let Some(全走査ならば解く数) = 1_u64.checked_shl(全走査でずらす幅) else {
            panic!("全走査の部分集合の数が桁あふれした: 点の数 {入れてよい点の数}");
        };
        Self {
            階層の走査が解いた数: 解いた数,
            全走査ならば解く数,
        }
    }

    /// 1回も解いていない状態。
    pub fn 零() -> Self {
        Self::default()
    }

    /// 2つの区間の回数を足した回数。
    /// 注意: 桁あふれで頭打ちにせず落とす。頭打ちにすると、費用の主張が黙って小さい値へ倒れる。
    pub fn 足す(self, 相手: Self) -> Self {
        let (Some(階層の走査が解いた数), Some(全走査ならば解く数)) = (
            self.階層の走査が解いた数.checked_add(相手.階層の走査が解いた数),
            self.全走査ならば解く数.checked_add(相手.全走査ならば解く数),
        ) else {
            panic!("解いた回数の合計が桁あふれした: {self:?} と {相手:?}");
        };
        Self {
            階層の走査が解いた数,
            全走査ならば解く数,
        }
    }

    /// 階層の走査が実際に解いた連立の数。
    pub fn 階層の走査が解いた数(&self) -> u64 {
        self.階層の走査が解いた数
    }

    /// 取りうる部分集合を全部走査したならば解いたはずの連立の数。
    pub fn 全走査ならば解く数(&self) -> u64 {
        self.全走査ならば解く数
    }
}
