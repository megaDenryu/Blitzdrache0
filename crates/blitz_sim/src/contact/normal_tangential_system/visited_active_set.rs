//! 有効集合の組み替えが既に通った集合の記録(判断12・判断13)。担当するのは、通った集合を印し、同じ集合へ戻ったかを
//! 答えることである。有効集合(`active_set`)から分けているのは、あちらが1つの集合であり、こちらが集合の集まりだからである。
//! 組み替えは行を外す向きと入れ直す向きの両方を持ち、同じ点が何度も出入りしうる。したがって「1点につき出入り各1回」を
//! 前提にした回数の上限では終了を保証できない。接触点の上限が8であるため取りうる集合は256個であり、通った集合を
//! 全部覚えれば、組み替えは高々256回で新しい集合を作れなくなる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

use super::active_set::法線と接線の連立の有効集合;

// 有効集合が取りうる状態の数。接触点の上限8のビット並びで表すため2の8乗である。
const 有効集合が取りうる状態の数: usize = 256;

/// 有効集合の組み替えが既に通った集合の記録。
pub(super) struct 通った有効集合の記録 {
    通ったか: [bool; 有効集合が取りうる状態の数],
}

impl 通った有効集合の記録 {
    /// 1つも通っていない記録。
    pub(super) fn 空() -> Self {
        Self {
            通ったか: [false; 有効集合が取りうる状態の数],
        }
    }

    /// 初めて通る集合なら印して真を返す。既に通っていれば印さずに偽を返す(組み替えが巡回している)。
    pub(super) fn 初めて通るなら印す(&mut self, 有効集合: &法線と接線の連立の有効集合) -> bool {
        let 添字 = usize::from(有効集合.ビット並び());
        let 初めて = !self.通ったか[添字];
        self.通ったか[添字] = true;
        初めて
    }
}
