//! Issue #103の段階A2と段階A3が測る設計候補の軸(判断13。試験と計器の専用)。本番はどの軸も1つ目の枝である。
//! 1つ目の列挙は、擬似逆の右辺の判定 |β_k| ≤ δ_k が何と比べるかを決める。本番は行ごとの解けたと見なす許容差で比べ、
//! 候補(α)は何とも比べず偽の固有値でない向きを全部解き、候補(θ)は接線の雑音の床へ安全率を掛けた1つの長さで比べ、
//! 候補(θ')は基準原点に相対な座標から導いた行ごとの許容差で比べる(候補(ζ)の式を擬似逆の採否だけへ届かせた枝)。
//! 段階A5の枝は、行ごとの許容差そのものを当てず、座標も姿勢も読まない規則(増分の大きさ、または不確かさの率)で捨てる。
//! 2つ目の列挙は、行の解けたと見なす許容差 δ_i を世界の粗い位置の刻みから導くか、衝突の問い合わせの基準原点に相対な
//! 座標の刻みから導くか(候補(ζ))を決める。3つ目の列挙は、偽の固有値と見なす下限を連立方程式の次数と機械イプシロンから
//! 導くか、最大の固有値への相対比から導くか(候補(η))を決める。
//! 3つの列挙を1つのファイルへ置くのは、どれも同じ1回の計測で同時に振る解法の取り決めの軸であり、1つだけを持つ計測が
//! 無いためである(`tolerance_reach`が2つの軸を1つのファイルへ置くのと同じ理由)。
//! どの枝も本番の既定ではない。本番の解法はこの3つの列挙の存在を知らない。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::symmetric_system::座標を読まない右辺の向きの捨て方;

/// 擬似逆の右辺の判定 |β_k| ≤ δ_k が、行ごとに何を δ_i として比べるか(候補(α)と候補(θ)の軸)。
/// 偽の固有値の判定はどの枝でも残る。この軸は擬似逆の採否だけへ届き、行を積む閾値と受理の判定(A・B1・B4)へは届かない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 擬似逆が右辺の向きを捨てる判定の当て方 {
    /// 行ごとの受理の許容差を向きへ積み上げた δ_k と比べ、内側の向きを捨てる(本番の形)。
    行ごとの許容差で捨てる,
    /// 右辺の判定を当てず、偽の固有値でない向きを全部解く(候補(α))。
    捨てずに真の向きを全部解く,
    /// 接線の雑音の床へ安全率を掛けた1つの長さを全部の行の δ_i に据えて比べる(候補(θ))。受理の倍率は掛けない。
    接線の雑音の床へ安全率を掛けた長さで捨てる { 長さメートル: f32 },
    /// 衝突の問い合わせの基準原点に相対な座標の刻みから導いた行ごとの δ_i で比べる(候補(θ'))。受理の倍率は掛けない。
    基準原点に相対な座標から導く許容差で捨てる,
    /// 行ごとの許容差を当てず、座標も姿勢も読まない規則で捨てる(段階A5の2つの枝)。受理の倍率は掛けない。
    座標を読まない判定で捨てる {
        捨て方: 座標を読まない右辺の向きの捨て方
    },
}

/// 行の解けたと見なす許容差 δ_i を、どの座標の表現の刻みから導くか(候補(ζ)の軸)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 解けたと見なす許容差を導く座標の由来 {
    /// 2つの点の世界位置の粗い位置の刻みから導く(本番の形)。
    粗い位置の刻みから導く,
    /// 2つの点の、衝突の問い合わせの基準原点に相対な座標の刻みから導く(候補(ζ))。
    基準原点に相対な座標の刻みから導く,
}

/// 擬似逆が偽の固有値と見なす下限を、どの取り決めで導くか(候補(η)の軸)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 偽の固有値の下限を導く取り決め {
    /// 最大の固有値へ、連立方程式の次数の上界と単精度の機械イプシロンを掛ける(本番の形)。
    次数と機械イプシロンから導く,
    /// 最大の固有値へ、指定の相対比を掛ける(候補(η)。階数不足の向きを覆う帯を相対比で置く)。
    最大の固有値への相対比から導く { 相対比: f32 },
}
