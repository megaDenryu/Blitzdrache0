//! Issue #103の段階A2が測る2つの設計候補の軸(判断13。試験と計器の専用)。本番はどちらも1つ目の枝である。
//! 候補(α)は、擬似逆が右辺の固有の向きを捨てる判定 |β_k| ≤ δ_k を無効にし、偽の固有値でない向きを全部解く枝である。
//! 候補(ζ)は、行の解けたと見なす許容差 δ_i を、世界の粗い位置の刻みでなく衝突の問い合わせの基準原点に相対な座標の
//! 刻みから導く枝である。前者は「捨てるかどうか」を、後者は「比べる δ をどこから採るか」を差し替える。
//! 2つの列挙を1つのファイルへ置くのは、どちらも段階A2の1回の計測で同時に振る解法の取り決めの軸であり、
//! 片方だけを持つ計測が段階A2に無いためである(`tolerance_reach`が2つの軸を1つのファイルへ置くのと同じ理由)。
//! どちらの枝も本番の既定ではない。本番の解法はこの2つの列挙の存在を知らない。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

/// 擬似逆が右辺の固有の向きを捨てる判定を当てるか(候補(α)の軸)。偽の固有値 λ_k ≤ λ_max n ε の判定はどちらの枝でも残る。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 擬似逆が右辺の向きを捨てる判定の当て方 {
    /// 行ごとの受理の許容差を向きへ積み上げた δ_k と |β_k| を比べ、内側の向きを捨てる(本番の形)。
    行ごとの許容差で捨てる,
    /// 右辺の判定を当てず、偽の固有値でない向きを全部解く(候補(α))。
    捨てずに真の向きを全部解く,
}

/// 行の解けたと見なす許容差 δ_i を、どの座標の表現の刻みから導くか(候補(ζ)の軸)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 解けたと見なす許容差を導く座標の由来 {
    /// 2つの点の世界位置の粗い位置の刻みから導く(本番の形)。
    粗い位置の刻みから導く,
    /// 2つの点の、衝突の問い合わせの基準原点に相対な座標の刻みから導く(候補(ζ))。
    基準原点に相対な座標の刻みから導く,
}
