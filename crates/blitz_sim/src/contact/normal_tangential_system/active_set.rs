//! 法線と接線の連立の中で、いま法線の反力を持たせている接触点の集合(判断12・判断13)。
//! 接線の行はこの集合に入る点だけが持つ。法線の行を外した点の接線の行も外すのは、その点に法線反力が無い以上
//! 静止摩擦の乗数を支えるものが無いためである(その点の接線の乗数は零へ解放する)。
//! 組み替えの順は接触点の番号の昇順で決め、最初に見つかった点を選ぶ(2回実行のビット一致のため)。
//! 接触点の上限が8であるためビット並び1つで表す。組み替えが取りうる集合の全部が256個であることがこの表し方から
//! 直に読めるため、通った集合を記録して巡回を検出する側(`visited_active_set`)の受け皿の大きさが定まる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_collision::contact_set::接触点の上限;

/// 接触点集合1つの中で、いま法線の反力を持たせている点の集合。第k番のビットが第k番の接触点である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct 法線と接線の連立の有効集合 {
    ビット並び: u8,
}

impl 法線と接線の連立の有効集合 {
    /// 1点も入れていない集合。呼び出し側が押し戻している点を順に入れて開始の集合にする。
    pub(super) fn 空() -> Self {
        Self { ビット並び: 0 }
    }

    /// この接触点の法線の行がいま有効か。偽の点は接線の行も連立へ入らない。
    pub fn 有効か(&self, 点の番号: usize) -> bool {
        self.ビット並び & 点の番号のビット(点の番号) != 0
    }

    /// 更新後の法線の乗数が負に振れた点を外す。外した点の法線の乗数は零へ解放する。
    pub(super) fn 外す(&mut self, 点の番号: usize) {
        self.ビット並び &= !点の番号のビット(点の番号);
    }

    /// 混合の補正の後になお食い込む点を入れる。
    pub(super) fn 入れる(&mut self, 点の番号: usize) {
        self.ビット並び |= 点の番号のビット(点の番号);
    }

    /// 集合そのものを表すビット並び。通った集合の記録がこれを添字にする。
    pub(super) fn ビット並び(&self) -> u8 {
        self.ビット並び
    }
}

// 第k番の接触点を表すビット。入力同士が対等でない(番号からビットへの写像である)が、集合の状態に依らない純粋な
// 変換であるため自由関数に置く。
// 注意: 接触点の上限以上の番号は衝突数学層の不変条件の破れであり、ここで落とす。
fn 点の番号のビット(点の番号: usize) -> u8 {
    assert!(点の番号 < 接触点の上限, "接触点の番号が接触点の上限を超えた: {点の番号}");
    1u8 << 点の番号
}
