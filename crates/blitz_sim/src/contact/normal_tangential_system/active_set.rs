//! 法線と接線の連立の中で、いま法線の反力を持たせている接触点の集合(判断12・判断13)。
//! 接線の行はこの集合に入る点だけが持つ。法線の行を外した点の接線の行も外すのは、その点に法線反力が無い以上
//! 静止摩擦の乗数を支えるものが無いためである(その点の接線の乗数は零へ解放する)。
//! 接触点の上限が8であるためビット並び1つで表す。取りうる集合が高々256個であることがこの表し方から直に読めるため、
//! 部分集合を走査して相補条件を満たすものを選ぶ側(`subset_search`)の走査が有限であることも表し方から読める。
//! 部分集合の枚挙(全体の部分集合を大きい方から数え下げる並び)と、集合が含む点の数を数えることをこの型が持つのは、
//! どちらもビット並びの表し方そのものの操作であり、走査の側へ生のビット並びを持ち出させないためである。
//! 走査の順と選び方は`candidate`が持ち、この型は集合そのものだけを表す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_collision::contact_set::接触点の上限;

/// 接触点集合1つの中で、いま法線の反力を持たせている点の集合。第k番のビットが第k番の接触点である。
/// 全順序を持つのは、退化した候補の決着で最後にこの集合そのものを比べるためである(`candidate`)。
/// 順はビット並びの大小であり、同じ入力から同じ候補が選ばれることだけを保証する。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
#[repr(transparent)]
pub struct 法線と接線の連立の有効集合 {
    ビット並び: u8,
}

impl 法線と接線の連立の有効集合 {
    /// ビット並びが表す集合。走査する側が候補のビット並びの部分集合を順に渡す。
    pub(super) fn ビット並びから生成する(ビット並び: u8) -> Self {
        Self { ビット並び }
    }

    /// この接触点の法線の行がいま有効か。偽の点は接線の行も連立へ入らない。
    /// 注意: 接触点の上限以上の番号は衝突数学層の不変条件の破れであり、ここで落とす。
    pub fn 有効か(&self, 点の番号: usize) -> bool {
        assert!(点の番号 < 接触点の上限, "接触点の番号が接触点の上限を超えた: {点の番号}");
        self.ビット並び & (1u8 << 点の番号) != 0
    }

    /// この集合が含む接触点の数。有効集合を探す走査は、この数の階層で部分集合を分けて調べる。
    pub(super) fn 点の数を数える(&self) -> usize {
        usize::try_from(self.ビット並び.count_ones()).unwrap_or(接触点の上限)
    }

    /// 1点も含まない集合か。部分集合の枚挙はこの集合を最後に返して終わる。
    pub(super) fn 一点も含まないか(&self) -> bool {
        self.ビット並び == 0
    }

    /// 全体の部分集合を大きい方から数え下げる枚挙で、この集合の次に来る部分集合。
    /// 前提: この集合が全体の部分集合であり、一点も含まない集合でないこと。走査がその順で呼ぶ。
    pub(super) fn 全体の中で次に小さい部分集合(&self, 全体: &Self) -> Self {
        Self {
            ビット並び: (self.ビット並び - 1) & 全体.ビット並び,
        }
    }
}
