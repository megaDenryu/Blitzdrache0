//! 法線と接線の連立の中で、いま法線の反力を持たせている接触点の集合(判断12・判断13)。
//! 接線の行はこの集合に入る点だけが持つ。法線の行を外した点の接線の行も外すのは、その点に法線反力が無い以上
//! 静止摩擦の乗数を支えるものが無いためである(その点の接線の乗数は零へ解放する)。
//! 組み替えの順は接触点の番号の昇順で決め、最初に見つかった点を選ぶ(2回実行のビット一致のため)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_collision::contact_set::接触点の上限;

/// 接触点集合1つの中で、いま法線の反力を持たせている点の集合。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 法線と接線の連立の有効集合 {
    有効か: [bool; 接触点の上限],
}

impl 法線と接線の連立の有効集合 {
    /// 1点も入れていない集合。呼び出し側が押し戻している点を順に入れて開始の集合にする。
    pub(super) fn 空() -> Self {
        Self {
            有効か: [false; 接触点の上限],
        }
    }

    /// この接触点の法線の行がいま有効か。偽の点は接線の行も連立へ入らない。
    pub fn 有効か(&self, 点の番号: usize) -> bool {
        self.有効か[点の番号]
    }

    /// 更新後の法線の乗数が負に振れた点を外す。外した点の法線の乗数は零へ解放する。
    pub(super) fn 外す(&mut self, 点の番号: usize) {
        self.有効か[点の番号] = false;
    }

    /// 混合の補正の後になお食い込む点を入れる。
    pub(super) fn 入れる(&mut self, 点の番号: usize) {
        self.有効か[点の番号] = true;
    }
}
