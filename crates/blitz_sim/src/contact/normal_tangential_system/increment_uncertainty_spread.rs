//! 固有の向きを解いたときの増分と、その増分が行列自身の丸めでどれだけ動きうるかの率の広がり(Issue #103の
//! 段階A5の計測5と計測6。試験と計器の専用)。固有値の相対値だけを見る`固有値を最大で割った相対値の広がり`から
//! 分けているのは、あちらが行列の固有値の並びだけを読む型であり、こちらが右辺の射影 β_k を併せて読む型だからである。
//!
//! この広がりが要るのは、右辺の側の判定 |β_k| ≤ δ_k を当てずに向きを捨てる判定を作れるかを、実測で確かめるためである。
//! 行列の不確かさは正本が既に定める偽の固有値の下限 λ_max n ε であり、固有値 λ_k がその不確かさだけ動くと、
//! その向きを解いたときの増分 |β_k| ÷ λ_k は相対で (λ_max n ε) ÷ λ_k だけ動く。この率が1に近い向きは、
//! 増分が行列の丸めによって決まっていない向きである。率で分けられるなら、壊す向きと無害な向きのあいだに帯が開く。
//! 増分は場面ごとに大きさが違うため、そのまま桁で数えても場面をまたいで比べられない。そこで、右辺をいちばん硬い
//! 向きで解いたときに必ず要る増分 ‖b‖ ÷ λ_max で割って正規化する。この分母は右辺が零でない限り零にならない。
//! 数えるのは、偽の固有値の下限より上に居る向きだけである。下限より下の向きは本番も候補も捨てるため、
//! そこを数えると「どちらの形でも捨てる向き」が壊す側へ大量に入り、分ける帯の有無を読めなくなる。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::decade_histogram::桁ごとの度数;
use super::solution_breakdown::単精度の解の内訳;

// 正規化した増分がこの値以上の向きを「壊す向き」と読む。段階A2の追補の表40が測った2つの向き(壊す向きの増分は
// この正規化で 3.1e2、無害な向きは 3.4e-3)のあいだは5桁空いており、その帯の上の端に近い側へ線を置く。
// 1倍に置くと、λ_max の0.28倍という物理の向きまで壊す側へ入る(その向きの増分は分母の3.6倍になる)。
const 壊すと読む正規化した増分の下端: f32 = 100.0;

/// 複数の求解を通した、増分と不確かさの率の広がり。
pub(in crate::contact) struct 増分と不確かさの率の広がり {
    数えた求解の数: usize,
    不確かさの率の度数: 桁ごとの度数,
    正規化した増分の度数: 桁ごとの度数,
    壊す向きの本数: usize,
    無害な向きの本数: usize,
    壊す向きの不確かさの率の最小: f32,
    無害な向きの不確かさの率の最大: f32,
}

impl 増分と不確かさの率の広がり {
    pub(in crate::contact) fn 零から始める() -> Self {
        Self {
            数えた求解の数: 0,
            不確かさの率の度数: 桁ごとの度数::範囲から始める(-8, 10),
            正規化した増分の度数: 桁ごとの度数::範囲から始める(-8, 12),
            壊す向きの本数: 0,
            無害な向きの本数: 0,
            壊す向きの不確かさの率の最小: f32::INFINITY,
            無害な向きの不確かさの率の最大: 0.0,
        }
    }

    /// 1回の求解の固有の向きを数える。最大の固有値か右辺の大きさが正でない求解は数えない。
    pub(in crate::contact) fn 一回の求解を数える(&mut self, 内訳: &単精度の解の内訳) {
        let 正規化の分母 = 内訳.右辺をいちばん硬い向きで解いたときの増分();
        if 内訳.最大の固有値 <= 0.0 || 正規化の分母 <= 0.0 {
            return;
        }
        self.数えた求解の数 += 1;
        for 向き in &内訳.固有の向きごと {
            if 向き.固有値 <= 内訳.偽の固有値の下限 {
                continue;
            }
            let 率 = 内訳.偽の固有値の下限 / 向き.固有値;
            let 正規化した増分 = (向き.右辺の射影 / 向き.固有値).abs() / 正規化の分母;
            self.不確かさの率の度数.一つ数える(率);
            self.正規化した増分の度数.一つ数える(正規化した増分);
            if 正規化した増分 >= 壊すと読む正規化した増分の下端 {
                self.壊す向きの本数 += 1;
                self.壊す向きの不確かさの率の最小 = self.壊す向きの不確かさの率の最小.min(率);
            } else {
                self.無害な向きの本数 += 1;
                self.無害な向きの不確かさの率の最大 = self.無害な向きの不確かさの率の最大.max(率);
            }
        }
    }

    /// 壊す向きと無害な向きを不確かさの率で分けられる帯。壊す向きの最小が無害な向きの最大を上回るなら、その2つで
    /// 挟んだ範囲が帯である。上回らなければ、1つの率で2つの群を分けられない。
    pub(in crate::contact) fn 二つの群を分ける帯(&self) -> Option<(f32, f32)> {
        (self.無害な向きの不確かさの率の最大 < self.壊す向きの不確かさの率の最小)
            .then_some((self.無害な向きの不確かさの率の最大, self.壊す向きの不確かさの率の最小))
    }

    /// 表へ綴る形。
    pub(in crate::contact) fn 綴り(&self) -> String {
        let 帯 = match self.二つの群を分ける帯() {
            Some((下端, 上端)) => format!("{下端:.3e}〜{上端:.3e}(桁の幅{:.2})", (上端 / 下端).log10()),
            None => "無し(2つの群が重なる)".to_owned(),
        };
        format!(
            "求解={}件 不確かさの率の度数[{}] 正規化した増分の度数[{}] 壊す向き={}本(率の最小={:.3e}) 無害な向き={}本(率の最大={:.3e}) 分ける帯={帯}",
            self.数えた求解の数,
            self.不確かさの率の度数.綴り(),
            self.正規化した増分の度数.綴り(),
            self.壊す向きの本数,
            self.壊す向きの不確かさの率の最小,
            self.無害な向きの本数,
            self.無害な向きの不確かさの率の最大
        )
    }
}
