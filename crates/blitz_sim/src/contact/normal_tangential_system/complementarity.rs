//! 1つの有効集合の解が法線の相補条件を満たすかの判定(判断12・判断13)。判定は3つである。
//! 有効な点の更新後の法線の乗数が0以上であること、その乗数がこの細分に詰めてよい長さから決まる上限を超えないこと、
//! 有効でない点の更新後の隔たりが表現の刻みを超えて負でないことである。
//! 上限を超える候補を満たさないものとして落とすのは、深い初期重なりの回復中に粘着の候補を解かないためである。
//! 上限は「1細分で詰めてよい貫通の長さ」であり、その上限で切り詰めた解は連立の解ではなくなる。切り詰めた値で
//! 円錐を判定すると、回復中の細分だけ実効の摩擦が変わる。回復中は法線だけの連立が上限を守って解く。
//! 探す工程(`subset_search`)から分けているのは、こちらが1つの集合を見る判定であり、あちらが全部の部分集合を
//! 走査して1つへ絞る工程だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

use blitz_math::メートル;

use super::active_set::法線と接線の連立の有効集合;
use super::solution::接触点集合の法線と接線の同時解;
use super::system::接触点集合の法線と接線の連立;
use crate::xpbd::ラグランジュ乗数;

impl 接触点集合の法線と接線の連立 {
    /// この解が法線の相補条件を満たすか。満たさない集合は候補にしない。
    pub(super) fn 相補条件を満たすか(
        &self, 同時解: &接触点集合の法線と接線の同時解, 有効集合: &法線と接線の連立の有効集合
    ) -> bool {
        (0..self.点の数()).all(|点の番号| {
            if 有効集合.有効か(点の番号) {
                self.有効な点の乗数が範囲に収まるか(同時解, 点の番号)
            } else {
                !self.補正の後に食い込むか(同時解, 点の番号)
            }
        })
    }

    // 有効な点の更新後の法線の乗数が0以上で、この細分の乗数の上限も超えないか。
    fn 有効な点の乗数が範囲に収まるか(&self, 同時解: &接触点集合の法線と接線の同時解, 点の番号: usize) -> bool {
        self.法線の一行を読む(点の番号).is_some_and(|一行| {
            let 更新後 = 一行.法線のラグランジュ乗数() + 同時解.一点の法線の乗数の増分(点の番号);
            更新後 >= ラグランジュ乗数::零() && 更新後 <= 一行.乗数の上限()
        })
    }

    // 有効でない点が、求めた増分を適用してもなお表現の刻みを超えて食い込むか。
    fn 補正の後に食い込むか(&self, 同時解: &接触点集合の法線と接線の同時解, 点の番号: usize) -> bool {
        self.法線の一行を読む(点の番号).is_some_and(|一行| {
            let 補正後の隔たり = 一行.隔たり() + self.増分が動かす隔たり(点の番号, 同時解);
            !一行.動かせない組か() && 補正後の隔たり < 一行.隔たりの表現の刻み() * -1.0
        })
    }

    // 求めた増分がこの点の法線の隔たりを動かす長さ Σ_j W_ij Δλ_j。有効でない点の解放の増分も含む。
    fn 増分が動かす隔たり(&self, 点の番号: usize, 同時解: &接触点集合の法線と接線の同時解) -> メートル {
        let Some(自分) = self.法線の一行を読む(点の番号) else {
            return メートル::生成する(0.0);
        };
        let mut 合計 = メートル::生成する(0.0);
        for 相手の番号 in 0..self.点の数() {
            if let Some(法線の行) = self.法線の一行を読む(相手の番号) {
                合計 = 合計 + 同時解.一点の法線の乗数の増分(相手の番号) * 自分.勾配().交差の寄与(法線の行.勾配());
            }
            if let Some(接線の行) = self.接線の一行を読む(相手の番号) {
                合計 = 合計 + 同時解.一点の接線の乗数の増分(相手の番号) * 自分.勾配().交差の寄与(接線の行.勾配());
            }
        }
        合計
    }
}
