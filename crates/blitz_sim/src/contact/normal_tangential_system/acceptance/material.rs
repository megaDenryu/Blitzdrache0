//! 混合連立の受理の判定の材料と、材料で判定する工程(判断13)。材料は、行を積まなかった点ごとの残差(A)・積んだ接線の
//! 行ごとの元の行空間の残差(B1)・相補条件の判定(B2)・円錐の判定(B3)・行ごとの捨てた成分を戻した量(B4)の5つである。
//! 判定の順は A・B1・B2・B4 の数値の契約を先に見て、全部を満たしたときだけ B3 の円錐を見る。数値の契約を破った解は
//! 連立の解でないため、その解が作る乗数で物理の状態遷移(粘着から滑走)を決めてはならない。
//! 番号で記す口が同じ番号を2度受けたら後の値が残る。材料は反復ごとに空から組み、同じ点を2度記す呼び出しはバグである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_collision::contact_set::接触点の上限;

use super::super::super::symmetric_system::法線と接線の連立の行の上限;
use super::residual_bound::残差と受理の許容差;
use super::result::{受理の契約を破った理由, 混合連立の受理の結果};

/// 混合連立の受理の判定の材料。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 混合連立の受理の材料 {
    積まなかった点の残差: [Option<残差と受理の許容差>; 接触点の上限],
    積んだ接線の行の残差: [Option<残差と受理の許容差>; 接触点の上限],
    捨てた成分を戻した残差: [Option<残差と受理の許容差>; 法線と接線の連立の行の上限],
    相補条件を満たすか: bool,
    円錐の内側か: bool,
}

impl 混合連立の受理の材料 {
    /// 何も記していない材料。相補条件と円錐は「満たさない」から始め、記し忘れが受理にならないようにする。
    pub fn 空から始める() -> Self {
        Self {
            積まなかった点の残差: [None; 接触点の上限],
            積んだ接線の行の残差: [None; 接触点の上限],
            捨てた成分を戻した残差: [None; 法線と接線の連立の行の上限],
            相補条件を満たすか: false,
            円錐の内側か: false,
        }
    }

    /// (A) C_t ≤ δ のために行を積まなかった点の、元の接線拘束に対する残差 C_t とその閾値 δ。
    pub fn 積まなかった点を記す(&mut self, 点の番号: usize, 残差: 残差と受理の許容差) {
        self.積まなかった点の残差[点の番号] = Some(残差);
    }

    /// (B1) 積んだ接線の行の、元の行空間で測った残差とその行の受理の許容差。
    pub fn 積んだ接線の行を記す(&mut self, 点の番号: usize, 残差: 残差と受理の許容差) {
        self.積んだ接線の行の残差[点の番号] = Some(残差);
    }

    /// (B4) 抜き出した連立の第k行へ捨てた成分を戻した量と、その行の受理の許容差。
    pub fn 捨てた成分を戻した残差を記す(&mut self, 行の番号: usize, 残差: 残差と受理の許容差) {
        self.捨てた成分を戻した残差[行の番号] = Some(残差);
    }

    /// (B2) 非貫通の相補条件の判定。
    pub fn 相補条件の判定を記す(&mut self, 満たすか: bool) {
        self.相補条件を満たすか = 満たすか;
    }

    /// (B3) 接触点集合の単位のクーロン円錐の判定。
    pub fn 円錐の判定を記す(&mut self, 内側か: bool) {
        self.円錐の内側か = 内側か;
    }

    /// 5つの契約で判定する。数値の契約(A・B1・B2・B4)を先に見て、最初に破れた1つを理由にする。
    pub fn 判定する(&self) -> 混合連立の受理の結果 {
        if let Some(理由) = self.数値の契約を破った理由() {
            return 混合連立の受理の結果::数値の契約を破った(理由);
        }
        if !self.円錐の内側か {
            return 混合連立の受理の結果::円錐を超えた;
        }
        混合連立の受理の結果::受理した
    }

    fn 数値の契約を破った理由(&self) -> Option<受理の契約を破った理由> {
        if let Some((点の番号, 残差)) = 最初に許容差を超えた(&self.積まなかった点の残差) {
            return Some(受理の契約を破った理由::積まなかった点の残差が許容差を超えた { 点の番号, 残差 });
        }
        if let Some((点の番号, 残差)) = 最初に許容差を超えた(&self.積んだ接線の行の残差) {
            return Some(受理の契約を破った理由::積んだ接線の行の残差が許容差を超えた { 点の番号, 残差 });
        }
        if !self.相補条件を満たすか {
            return Some(受理の契約を破った理由::相補条件を満たさない);
        }
        if let Some((行の番号, 残差)) = 最初に許容差を超えた(&self.捨てた成分を戻した残差) {
            return Some(受理の契約を破った理由::捨てた成分を戻した残差が許容差を超えた { 行の番号, 残差 });
        }
        None
    }
}

// 記された残差のうち、番号の昇順で最初に許容差を超えたものとその番号。
fn 最初に許容差を超えた(残差の並び: &[Option<残差と受理の許容差>]) -> Option<(usize, 残差と受理の許容差)> {
    残差の並び
        .iter()
        .enumerate()
        .find_map(|(番号, 残差)| 残差.filter(|残差| !残差.許容差の内側か()).map(|残差| (番号, 残差)))
}
