//! 混合連立の受理の判定の反証(判断13、Issue #59の第4段階の段階C)。担当するのは、5つの契約のどれか1つをわざと破る
//! 材料(残差が受理の許容差の1.5倍の行)で判定が型付きの結末で落ちること、全部を満たす材料だけが受理されること、
//! 数値の契約の破れが円錐の判定より先に答えられることを固定することである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::メートル;

use super::material::混合連立の受理の材料;
use super::residual_bound::残差と受理の許容差;
use super::result::{受理の契約を破った理由, 混合連立の受理の結果};

const 許容差の値: f32 = 2.0e-6;

fn 内側の残差() -> 残差と受理の許容差 {
    残差と受理の許容差::残差と許容差から生成する(メートル::生成する(-0.5 * 許容差の値), メートル::生成する(許容差の値))
}

// わざと破る材料。残差は受理の許容差の1.5倍であり、符号を負にして絶対値で判定することも同時に固定する。
fn 破る残差() -> 残差と受理の許容差 {
    残差と受理の許容差::残差と許容差から生成する(メートル::生成する(-1.5 * 許容差の値), メートル::生成する(許容差の値))
}

// 5つの契約を全部満たす材料。点0は行を積まず、点1〜3は行を積み、抜き出した連立は7行である。
fn 全部を満たす材料() -> 混合連立の受理の材料 {
    let mut 材料 = 混合連立の受理の材料::空から始める();
    材料.積まなかった点を記す(0, 内側の残差());
    for 点の番号 in 1..4 {
        材料.積んだ接線の行を記す(点の番号, 内側の残差());
    }
    for 行の番号 in 0..7 {
        材料.捨てた成分を戻した残差を記す(行の番号, 内側の残差());
    }
    材料.相補条件の判定を記す(true);
    材料.円錐の判定を記す(true);
    材料
}

#[test]
fn 全部の契約を満たす材料は受理される() {
    assert_eq!(全部を満たす材料().判定する(), 混合連立の受理の結果::受理した);
}

#[test]
fn 積まなかった点の残差が許容差の一点五倍なら数値の契約を破った結末で落ちる() {
    let mut 材料 = 全部を満たす材料();
    材料.積まなかった点を記す(0, 破る残差());
    assert_eq!(
        材料.判定する(),
        混合連立の受理の結果::数値の契約を破った(受理の契約を破った理由::積まなかった点の残差が許容差を超えた {
            点の番号: 0,
            残差: 破る残差()
        })
    );
}

#[test]
fn 積んだ接線の行の残差が許容差の一点五倍なら数値の契約を破った結末で落ちる() {
    let mut 材料 = 全部を満たす材料();
    材料.積んだ接線の行を記す(2, 破る残差());
    assert_eq!(
        材料.判定する(),
        混合連立の受理の結果::数値の契約を破った(受理の契約を破った理由::積んだ接線の行の残差が許容差を超えた {
            点の番号: 2,
            残差: 破る残差()
        })
    );
}

#[test]
fn 相補条件を満たさない材料は数値の契約を破った結末で落ちる() {
    let mut 材料 = 全部を満たす材料();
    材料.相補条件の判定を記す(false);
    assert_eq!(
        材料.判定する(),
        混合連立の受理の結果::数値の契約を破った(受理の契約を破った理由::相補条件を満たさない)
    );
}

#[test]
fn 捨てた成分を戻した残差が許容差の一点五倍なら数値の契約を破った結末で落ちる() {
    let mut 材料 = 全部を満たす材料();
    材料.捨てた成分を戻した残差を記す(6, 破る残差());
    assert_eq!(
        材料.判定する(),
        混合連立の受理の結果::数値の契約を破った(受理の契約を破った理由::捨てた成分を戻した残差が許容差を超えた {
            行の番号: 6,
            残差: 破る残差()
        })
    );
    assert!(材料.判定する().退避の枝へ落ちるか());
}

#[test]
fn 円錐を超えた材料は円錐を超えた結末であり退避の枝ではない() {
    let mut 材料 = 全部を満たす材料();
    材料.円錐の判定を記す(false);
    assert_eq!(材料.判定する(), 混合連立の受理の結果::円錐を超えた);
    assert!(!材料.判定する().退避の枝へ落ちるか());
}

#[test]
fn 数値の契約の破れは円錐の判定より先に答える() {
    let mut 材料 = 全部を満たす材料();
    材料.円錐の判定を記す(false);
    材料.積んだ接線の行を記す(1, 破る残差());
    assert!(材料.判定する().退避の枝へ落ちるか());
}

#[test]
fn 何も記していない材料は受理されない() {
    assert_eq!(
        混合連立の受理の材料::空から始める().判定する(),
        混合連立の受理の結果::数値の契約を破った(受理の契約を破った理由::相補条件を満たさない)
    );
}
