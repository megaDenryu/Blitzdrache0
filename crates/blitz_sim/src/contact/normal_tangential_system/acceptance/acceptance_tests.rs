//! 混合連立方程式の受理の判定が受理する側と円錐の側の反証(判断13、Issue #59の第4段階の段階C)。担当するのは、5つの契約を
//! 全部満たす材料だけが受理されること、残差が受理の許容差とちょうど等しい等号の境界が内側であること、円錐を超えた結末が
//! 退避の枝でないこと、数値の契約の破れが円錐の判定より先に答えられることを固定することである。
//! 数値の契約の破れの4つは `contract_breach_tests` が固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::メートル;

use super::material_fixture::{全部を満たす材料, 破る残差, 許容差の値};
use super::residual_bound::残差と受理の許容差;
use super::result::混合連立方程式の受理の結果;

#[test]
fn 全部の契約を満たす材料は受理される() {
    assert_eq!(全部を満たす材料().判定する(), 混合連立方程式の受理の結果::受理した);
}

// 等号の境界。残差の絶対値が受理の許容差とちょうど等しい行は内側であり、受理される。
#[test]
fn 残差が許容差とちょうど等しい材料は受理される() {
    let 等しい残差 =
        残差と受理の許容差::残差と許容差から生成する(メートル::生成する(-許容差の値), メートル::生成する(許容差の値));
    let mut 材料 = 全部を満たす材料();
    材料.積んだ接線の行を記す(3, 等しい残差);
    材料.積まなかった点を記す(0, 等しい残差);
    材料.捨てた成分を戻した残差を記す(0, 等しい残差);
    assert!(等しい残差.許容差の内側か());
    assert_eq!(材料.判定する(), 混合連立方程式の受理の結果::受理した);
}

#[test]
fn 円錐を超えた材料は円錐を超えた結末であり退避の枝ではない() {
    let mut 材料 = 全部を満たす材料();
    材料.円錐の判定を記す(false);
    assert_eq!(材料.判定する(), 混合連立方程式の受理の結果::円錐を超えた);
    assert!(!材料.判定する().退避の枝へ落ちるか());
}

#[test]
fn 円錐の判定を記して判定する口は円錐の側だけを書き換える() {
    assert_eq!(
        全部を満たす材料().円錐の判定を記して判定する(false),
        混合連立方程式の受理の結果::円錐を超えた
    );
    assert_eq!(全部を満たす材料().円錐の判定を記して判定する(true), 混合連立方程式の受理の結果::受理した);
}

#[test]
fn 数値の契約の破れは円錐の判定より先に答える() {
    let mut 材料 = 全部を満たす材料();
    材料.円錐の判定を記す(false);
    材料.積んだ接線の行を記す(1, 破る残差());
    assert!(材料.判定する().退避の枝へ落ちるか());
}
