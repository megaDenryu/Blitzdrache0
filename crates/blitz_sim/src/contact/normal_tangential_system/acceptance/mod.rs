//! 混合連立の受理の判定(判断13、Issue #59の第4段階の段階C)。有効集合の探索が定まった粘着の候補を、確定してよいかを
//! 5つの契約で判定する。契約は、行を積まなかった点の元の接線拘束に対する残差(A)・積んだ接線の行の元の行空間の残差(B1)・
//! 非貫通の相補条件(B2)・接触点集合の単位のクーロン円錐(B3)・擬似逆で捨てた成分を元の行へ戻した量(B4)である。
//! 探す工程(`subset_search`)から分けているのは、あちらが候補を選ぶ工程であり、こちらが選ばれた1つの候補を確定してよいかを
//! 見る判定だからである。判定は退避の枝の前にあり、数値の契約を破った候補は粘着の候補として確定せず、法線だけの連立へ
//! 落とす。円錐を超えた候補は従前どおり滑走への移行である。
//! 判定の材料は測った量そのものであり、連立を読まない。材料を測る工程と、測った量で判定する工程を分けるのは、
//! わざと δ を破る材料で判定が落ちることを、連立を組まずに固定するためである。
