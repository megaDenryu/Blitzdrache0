//! 1つの残差と、その残差を解けたと見なす受理の許容差の組(判断13)。混合連立方程式の受理の判定の5つの契約のうち、
//! 長さで比べる3つ(A・B1・B4)がこの組で判定する。残差と許容差を別々に運ぶと、どの許容差がどの残差の上限かが
//! 呼び出し側の並びの規律に依存するため、1つの値に束ねる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::メートル;

/// 残差と、その残差の上限である受理の許容差。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 残差と受理の許容差 {
    残差: メートル,
    許容差: メートル,
}

impl 残差と受理の許容差 {
    /// 残差は符号を持ってよい。判定は絶対値で行う。
    pub fn 残差と許容差から生成する(残差: メートル, 許容差: メートル) -> Self {
        Self { 残差, 許容差 }
    }

    /// 残差の絶対値が受理の許容差の内側(等しい場合を含む)か。
    pub fn 許容差の内側か(&self) -> bool {
        self.残差.値().abs() <= self.許容差.値()
    }

    /// 表へ綴る形「残差/許容差(比)」。診断の計器だけが読む。
    #[cfg(test)]
    pub fn 綴り(&self) -> String {
        format!("{:.3e}/{:.3e}(比{:.2})", self.残差.値(), self.許容差.値(), self.許容差に対する比())
    }

    /// |残差| ÷ 許容差。許容差が零で残差が非零なら無限大であり、どちらも零なら零である(零の行は内側である)。
    pub fn 許容差に対する比(&self) -> f32 {
        let (残差, 許容差) = (self.残差.値().abs(), self.許容差.値());
        if 許容差 > 0.0 {
            残差 / 許容差
        } else if 残差 > 0.0 {
            f32::INFINITY
        } else {
            0.0
        }
    }
}
