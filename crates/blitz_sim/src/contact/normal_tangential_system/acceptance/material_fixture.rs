//! 混合連立の受理の判定の反証が共有する材料(判断13)。5つの契約を全部満たす材料と、許容差の内側の残差と、わざと
//! 破る残差(受理の許容差の1.5倍)を作る。反証そのもの(`acceptance_tests`・`contract_breach_tests`)から分けているのは、
//! こちらが材料を組む工程であり、あちらが判定して固定する工程だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::メートル;

use super::material::混合連立の受理の材料;
use super::residual_bound::残差と受理の許容差;

pub(super) const 許容差の値: f32 = 2.0e-6;

pub(super) fn 内側の残差() -> 残差と受理の許容差 {
    残差と受理の許容差::残差と許容差から生成する(メートル::生成する(-0.5 * 許容差の値), メートル::生成する(許容差の値))
}

/// わざと破る材料。残差は受理の許容差の1.5倍であり、符号を負にして絶対値で判定することも同時に固定する。
pub(super) fn 破る残差() -> 残差と受理の許容差 {
    残差と受理の許容差::残差と許容差から生成する(メートル::生成する(-1.5 * 許容差の値), メートル::生成する(許容差の値))
}

/// 5つの契約を全部満たす材料。点0は行を積まず、点1〜3は行を積み、抜き出した連立は7行である。
pub(super) fn 全部を満たす材料() -> 混合連立の受理の材料 {
    let mut 材料 = 混合連立の受理の材料::空から始める();
    材料.積まなかった点を記す(0, 内側の残差());
    for 点の番号 in 1..4 {
        材料.積んだ接線の行を記す(点の番号, 内側の残差());
    }
    for 行の番号 in 0..7 {
        材料.捨てた成分を戻した残差を記す(行の番号, 内側の残差());
    }
    材料.相補条件の判定を記す(true);
    材料.円錐の判定を記す(true);
    材料
}
