//! 混合連立方程式の受理の判定の結末(判断13)。3枝である。受理した(解と仮の乗数を確定する)・円錐を超えた(粘着の候補を捨てて
//! 集合を滑走中へ移す)・数値の契約を破った(粘着の候補を捨てて法線だけの連立方程式を解き直す。集合は滑走中にしない)。
//! 円錐と数値の契約を別の枝にするのは、呼び出し側の後始末が違うためである。円錐の超過は物理の状態遷移(粘着から滑走)であり
//! 錨を置き直す。数値の契約の破れは解法の退避であり、錨も乗数もその反復の前のまま残す。
//! 破った契約の理由に点または行の番号と残差と許容差を持たせるのは、退避の件数・理由・残差を δ の倍率ごとに数える診断
//! (判断13の実装の細目の(3))がこの値をそのまま読むためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::residual_bound::残差と受理の許容差;

/// 混合連立方程式の受理の判定が破れたと判定した契約。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 受理の契約を破った理由 {
    /// (A) 行を積まなかった点の、元の接線拘束 C_t = 0 に対する残差が許容差を超えた。
    積まなかった点の残差が許容差を超えた {
        点の番号: usize, 残差: 残差と受理の許容差
    },
    /// (B1) 積んだ接線の行の、元の行空間で測った残差が受理の許容差を超えた。
    積んだ接線の行の残差が許容差を超えた {
        点の番号: usize, 残差: 残差と受理の許容差
    },
    /// (B2) 非貫通の相補条件を満たさない。
    相補条件を満たさない,
    /// (B4) 擬似逆で捨てた成分を元の行へ戻した量が、その行の受理の許容差を超えた。
    捨てた成分を戻した残差が許容差を超えた {
        行の番号: usize, 残差: 残差と受理の許容差
    },
}

impl 受理の契約を破った理由 {
    /// 破った契約の番号と残差の綴り。相補条件の破れは残差を持たない。診断の計器だけが読む。
    #[cfg(test)]
    pub fn 残差の綴り(&self) -> String {
        match self {
            Self::積まなかった点の残差が許容差を超えた { 点の番号, 残差 } => format!("点{点の番号} {}", 残差.綴り()),
            Self::積んだ接線の行の残差が許容差を超えた { 点の番号, 残差 } => format!("点{点の番号} {}", 残差.綴り()),
            Self::相補条件を満たさない => String::new(),
            Self::捨てた成分を戻した残差が許容差を超えた { 行の番号, 残差 } => format!("行{行の番号} {}", 残差.綴り()),
        }
    }

    /// 破った契約の名前。解けなかった連立方程式の読み取り(試験の場面)が結末の綴りとして持つ。
    #[cfg(test)]
    pub fn 契約の名前(&self) -> &'static str {
        match self {
            Self::積まなかった点の残差が許容差を超えた { .. } => "受理(A)積まなかった点の残差が許容差を超えた",
            Self::積んだ接線の行の残差が許容差を超えた { .. } => "受理(B1)積んだ接線の行の残差が許容差を超えた",
            Self::相補条件を満たさない => "受理(B2)相補条件を満たさない",
            Self::捨てた成分を戻した残差が許容差を超えた { .. } => "受理(B4)捨てた成分を戻した残差が許容差を超えた",
        }
    }
}

/// 混合連立方程式の受理の判定の結末。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 混合連立方程式の受理の結果 {
    /// 5つの契約を全部満たした。呼び出し側は解と仮の乗数を確定する。
    受理した,
    /// 数値の契約は満たすが、接触点集合の単位のクーロン円錐を超えた。呼び出し側は粘着の候補を捨てて滑走中へ移す。
    円錐を超えた,
    /// 数値の契約を破った。呼び出し側は粘着の候補を捨てて法線だけの連立方程式を解き直す(退避の枝)。
    数値の契約を破った(受理の契約を破った理由),
}

impl 混合連立方程式の受理の結果 {
    /// 退避の枝へ落ちる結末か。円錐の超過は退避ではない。
    pub fn 退避の枝へ落ちるか(&self) -> bool {
        matches!(self, Self::数値の契約を破った(_))
    }
}
