//! 混合連立方程式の受理の判定が数値の契約(A・B1・B2・B4)の破れを型付きの結末で返すことの反証(判断13、Issue #59の第4段階の
//! 段階C)。担当するのは、4つの契約のどれか1つをわざと破る材料(残差が受理の許容差の1.5倍の行)で、判定が破った契約の
//! 番号と残差を持つ結末で落ちることを固定することである。受理される側と円錐の側は `acceptance_tests` が固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::material_fixture::{全部を満たす材料, 破る残差};
use super::result::{受理の契約を破った理由, 混合連立方程式の受理の結果};

#[test]
fn 積まなかった点の残差が許容差の一点五倍なら数値の契約を破った結末で落ちる() {
    let mut 材料 = 全部を満たす材料();
    材料.積まなかった点を記す(0, 破る残差());
    assert_eq!(
        材料.判定する(),
        混合連立方程式の受理の結果::数値の契約を破った(受理の契約を破った理由::積まなかった点の残差が許容差を超えた {
            点の番号: 0,
            残差: 破る残差()
        })
    );
}

#[test]
fn 積んだ接線の行の残差が許容差の一点五倍なら数値の契約を破った結末で落ちる() {
    let mut 材料 = 全部を満たす材料();
    材料.積んだ接線の行を記す(2, 破る残差());
    assert_eq!(
        材料.判定する(),
        混合連立方程式の受理の結果::数値の契約を破った(受理の契約を破った理由::積んだ接線の行の残差が許容差を超えた {
            点の番号: 2,
            残差: 破る残差()
        })
    );
}

#[test]
fn 相補条件を満たさない材料は数値の契約を破った結末で落ちる() {
    let mut 材料 = 全部を満たす材料();
    材料.相補条件の判定を記す(false);
    assert_eq!(
        材料.判定する(),
        混合連立方程式の受理の結果::数値の契約を破った(受理の契約を破った理由::相補条件を満たさない)
    );
}

#[test]
fn 捨てた成分を戻した残差が許容差の一点五倍なら数値の契約を破った結末で落ちる() {
    let mut 材料 = 全部を満たす材料();
    材料.捨てた成分を戻した残差を記す(6, 破る残差());
    assert_eq!(
        材料.判定する(),
        混合連立方程式の受理の結果::数値の契約を破った(
            受理の契約を破った理由::捨てた成分を戻した残差が許容差を超えた {
                行の番号: 6,
                残差: 破る残差()
            }
        )
    );
    assert!(材料.判定する().退避の枝へ落ちるか());
}

#[test]
fn 何も記していない材料は受理されない() {
    assert_eq!(
        super::material::混合連立方程式の受理の材料::空から始める().判定する(),
        混合連立方程式の受理の結果::数値の契約を破った(受理の契約を破った理由::相補条件を満たさない)
    );
}
