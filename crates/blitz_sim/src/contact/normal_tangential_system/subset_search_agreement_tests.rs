//! 有効な点の数の階層で打ち切る走査が、取りうる部分集合を全部走査した結果と1ビットも変わらないことの検査
//! (判断13)。打ち切りの根拠は決着の第1の鍵が有効な点の数であることだけであり、その鍵を入れ替えると結果が
//! 変わる。基準の側(`full_scan_reference`)は決着の順を読まずに全部を解くため、この検査が壊れたことに気づける。
//! 材料の点の数を1から接触点の上限まで振り、余白の内側の点(生成時の隔たりが正である点)を混ぜる場合と混ぜない
//! 場合の両方を通すのは、相補条件を満たす集合が1つも無い場面と、点を外した集合だけが満たす場面の両方を出す
//! ためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use blitz_collision::contact_set::接触点の上限;

use super::random_system_fixture::無作為の法線と接線の連立の生成元;

// 1つの点の数と1つの混ぜ方につき組む材料の本数。
const 一組あたりの材料の本数: usize = 8;
const 材料の種: u64 = 20_260_906;

#[test]
fn 点の数の階層で打ち切る走査は全走査と同じ有効集合と同時解を返す() {
    let mut 生成元 = 無作為の法線と接線の連立の生成元::種から始める(材料の種);
    for 点の数 in 1..=接触点の上限 {
        for 余白の内側の点を混ぜるか in [false, true] {
            for 本目 in 0..一組あたりの材料の本数 {
                let 連立 = 生成元.次の連立を作る(点の数, 余白の内側の点を混ぜるか);
                let 階層 = 連立.点の数の多い階層から順に候補を探す();
                let 全部 = 連立.全部の部分集合を走査して候補を探す();
                let 場面 = format!("点の数{点の数}・余白の内側{余白の内側の点を混ぜるか}・{本目}本目");
                match (階層, 全部) {
                    (None, None) => (),
                    (Some(階層の候補), Some(全部の候補)) => {
                        assert_eq!(
                            階層の候補.有効集合のビット並び(),
                            全部の候補.有効集合のビット並び(),
                            "{場面}で階層の走査と全走査の有効集合が違う"
                        );
                        assert_eq!(階層の候補.同時解(), 全部の候補.同時解(), "{場面}で同時解が違う");
                    }
                    (階層の結果, 全部の結果) => panic!(
                        "{場面}で候補の有無が食い違った(階層 {} 全走査 {})",
                        階層の結果.is_some(),
                        全部の結果.is_some()
                    ),
                }
            }
        }
    }
}
