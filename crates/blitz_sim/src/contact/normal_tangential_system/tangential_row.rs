//! 法線と接線の連立の接線の1行(判断13)。接触点1つの2つの錨を結ぶ接線の向きと、その錨からの接線変位の長さを持ち、
//! 変位を零へ戻すことを求める行である。
//! 法線の行(`法線の隔たりを動かさない一行`)と別の型にしているのは、行が持つ量が違うためである。法線は隔たりと
//! 既存の乗数を持って有効集合の出し入れに答え、接線は向きと変位の長さを持って進めた乗数の組み立てに答える。
//! 既存の接線の乗数をこの型が持たないのは、進めた乗数 λ_t + Δs t の組み立てが接触点の状態の側の仕事であり、
//! この型が渡すのはその反復の向きだけで足りるためである。
//! 右辺は −C_t であり、解けたと見なす許容差 δ を含まない(2026-09-12の改訂)。δ は「この行を連立へ積むか」の閾値と
//! 受理の判定だけが読む。右辺を −(C_t − δ) にして長さ δ を意図して残す形は、細分0で残した δ が位置の残りと速度の運びの
//! 2経路で細分1へ二重に入り、接線の乗数を δ の倍率のぶん膨らませて円錐の判定を狂わせた(許容差依存の診断の段階A1〜A3)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::{メートル, ワールド, 方向};

use super::super::contact_projection_row::一行の二つの符号付き勾配;
use super::super::contact_projection_row::接触の射影に参加する点;
use super::acceptance::残差と受理の許容差;
#[cfg(test)]
use super::tolerance_scale::解けたと見なす許容差の倍率;

/// 接触点1つの、錨からの接線変位を零へ戻すことを求める行。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 錨の接線変位を零へ戻す一行 {
    勾配: 一行の二つの符号付き勾配,
    接線の向き: 方向<ワールド>,
    接線変位の長さ: メートル,
}

impl 錨の接線変位を零へ戻す一行 {
    /// 錨の接線変位からこの反復の1行を作る。接線の向きは第2の錨から第1の錨へ向かう単位方向である。
    /// 前提: 接線変位の長さは正である(零の点は連立へ入れず、既存の接線の乗数を保つ)。
    pub fn 錨と接線変位から生成する(
        第1の錨: 接触の射影に参加する点,
        第2の錨: 接触の射影に参加する点,
        接線の向き: 方向<ワールド>,
        接線変位の長さ: メートル,
    ) -> Self {
        Self {
            勾配: 一行の二つの符号付き勾配::接線の行として生成する(第1の錨, 第2の錨, 接線の向き),
            接線の向き,
            接線変位の長さ,
        }
    }

    pub fn 勾配(&self) -> &一行の二つの符号付き勾配 {
        &self.勾配
    }

    /// この反復でこの行が拘束する接線の向き t。進めた乗数はこの向きへ増分を足した値である。
    pub fn 接線の向き(&self) -> 方向<ワールド> {
        self.接線の向き
    }

    /// この行が零へ戻そうとしている錨からの接線変位の長さ C_t。元の接線拘束 C_t = 0 に対する残差そのものである。
    pub fn 接線変位の長さ(&self) -> メートル {
        self.接線変位の長さ
    }

    /// 元の接線拘束 C_t = 0 に対する残差 C_t と、この行の解けたと見なす許容差 δ の組。行を積むかどうかの閾値と、
    /// 積まなかった点の受理の判定(A)がこの組を読む。閾値の δ には受理の倍率を掛けない。
    pub fn 接線変位と許容差(&self) -> 残差と受理の許容差 {
        残差と受理の許容差::残差と許容差から生成する(self.接線変位の長さ, self.勾配.解けたと見なす許容差())
    }

    /// C_t がこの行の解けたと見なす許容差 δ の内側か。内側の行は「すでに数値上満たしている」として連立へ積まない。
    pub fn 許容差の内側か(&self) -> bool {
        self.接線変位と許容差().許容差の内側か()
    }

    /// 連立の右辺 −C_t。接線変位を零へ戻す向きであるため負である。δ を含まない。
    pub fn 連立の右辺(&self) -> メートル {
        self.接線変位の長さ * -1.0
    }

    /// 改訂前の右辺 −(C_t − 倍率×δ)。判断13の反証(4)(f)の対照(旧の形)を試験専用の当て方が読むためだけに残す。
    #[cfg(test)]
    pub fn 許容差へ倍率を掛けた連立の右辺(&self, 許容差の倍率: 解けたと見なす許容差の倍率) -> メートル {
        let 閉じられる長さ = self.接線変位の長さ - 許容差の倍率.許容差へ掛ける(self.勾配.解けたと見なす許容差());
        if 閉じられる長さ.値() > 0.0 {
            閉じられる長さ * -1.0
        } else {
            メートル::生成する(0.0)
        }
    }
}
