//! 法線と接線の連立の接線の1行(判断13)。接触点1つの2つの錨を結ぶ接線の向きと、その錨からの接線変位の長さを持ち、
//! 変位を零へ戻すことを求める行である。
//! 法線の行(`法線の隔たりを動かさない一行`)と別の型にしているのは、行が持つ量が違うためである。法線は隔たりと
//! 既存の乗数を持って有効集合の出し入れに答え、接線は向きと変位の長さを持って進めた乗数の組み立てに答える。
//! 既存の接線の乗数をこの型が持たないのは、進めた乗数 λ_t + Δs t の組み立てが接触点の状態の側の仕事であり、
//! この型が渡すのはその反復の向きだけで足りるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::{メートル, ワールド, 方向};

use super::super::contact_projection_row::一行の二つの符号付き勾配;
use super::super::contact_projection_row::接触の射影に参加する点;

/// 接触点1つの、錨からの接線変位を零へ戻すことを求める行。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 錨の接線変位を零へ戻す一行 {
    勾配: 一行の二つの符号付き勾配,
    接線の向き: 方向<ワールド>,
    接線変位の長さ: メートル,
}

impl 錨の接線変位を零へ戻す一行 {
    /// 錨の接線変位からこの反復の1行を作る。接線の向きは第2の錨から第1の錨へ向かう単位方向である。
    /// 前提: 接線変位の長さは正である(零の点は連立へ入れず、既存の接線の乗数を保つ)。
    pub fn 錨と接線変位から生成する(
        第1の錨: 接触の射影に参加する点,
        第2の錨: 接触の射影に参加する点,
        接線の向き: 方向<ワールド>,
        接線変位の長さ: メートル,
    ) -> Self {
        Self {
            勾配: 一行の二つの符号付き勾配::接線の行として生成する(第1の錨, 第2の錨, 接線の向き),
            接線の向き,
            接線変位の長さ,
        }
    }

    pub fn 勾配(&self) -> &一行の二つの符号付き勾配 {
        &self.勾配
    }

    /// この反復でこの行が拘束する接線の向き t。進めた乗数はこの向きへ増分を足した値である。
    pub fn 接線の向き(&self) -> 方向<ワールド> {
        self.接線の向き
    }

    /// 連立の右辺 −(C_t − δ)。接線変位を零へ戻す向きであるため負である。δ はこの行の世界位置が表せる刻みであり、
    /// それを下回る残りは補正で閉じられない。零へ戻す先を刻みのぶんだけ手前に置くのは、閉じられない残りに対して
    /// 乗数を積まないためである。積むと、細分ごとに刻みのぶんだけ余分な接線の乗数が乗り、クーロン円錐の判定が
    /// その余分を含んだ合力で行われる(世界の原点から遠い接触ほど保持できる傾きが下がる)。
    pub fn 連立の右辺(&self) -> メートル {
        let 閉じられる長さ = self.接線変位の長さ - self.勾配.解けたと見なす許容差();
        if 閉じられる長さ.値() > 0.0 {
            閉じられる長さ * -1.0
        } else {
            メートル::生成する(0.0)
        }
    }
}
