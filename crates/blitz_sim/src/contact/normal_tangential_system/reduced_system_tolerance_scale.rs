//! 抜き出した連立へ、試験の許容差の当て方を反映する後処理(Issue #59の数値契約の診断。試験と計器の専用)。
//! 抜き出し(`reduced_system`)から分けているのは、本番の抜き出しが当て方を1度も読まないためである。本番の
//! 組み立ての中へ当て方の分岐を置くと、本番の署名と本番の経路に当て方の型が現れる。ここへ寄せると、本番は
//! 当て方の存在を知らないまま組み立て、試験の構成のときだけこの後処理が値を差し替える。
//! 差し替えるのは4つである。全部の行の解けたと見なす許容差(候補(ζ)では導く座標の由来が変わる)と、接線の行の定数項
//! (右辺 −(C_t − δ) の δ の扱い)と、擬似逆の右辺の判定が比べる行ごとの許容差(候補(α)と候補(θ)と候補(θ'))と、
//! 偽の固有値と見なす下限の取り決め(候補(η))である。法線の隔たりが表現の刻みの内側かどうかの判定には掛けない。
//! あちらは「配置が1ビットも動かない」という表現の事実であり、解法の取り決めではないためである。
//! 基準原点に相対な座標から導く許容差は、どの適用規則でも行ごとに数えて持たせる。候補(θ')がそれを擬似逆へ渡し、
//! 2つの由来の δ_i を対で綴る計器が本番の適用規則の求解からも読むためである。
//! 本番と同じ当て方では、掛ける倍率が1倍で右辺の式も許容差の由来も本番と同じであるため、値は1ビットも変わらない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::super::symmetric_system::法線と接線の連立の行の上限;
use super::active_set::法線と接線の連立の有効集合;
use super::reduced_system::有効な行だけを抜き出した連立;
use super::row_order::抜き出した行の持ち主;
use super::system::接触点集合の法線と接線の連立;
use super::tolerance_candidate::擬似逆が右辺の向きを捨てる判定の当て方;

impl 有効な行だけを抜き出した連立 {
    /// 組み立てた行ごとの許容差と、接線の行の定数項と、擬似逆へ渡す2つの入力へ適用規則を反映する。
    /// 本番と同じ適用規則なら値は1ビットも変わらない。
    pub(super) fn 試験の許容差の当て方を反映する(
        &mut self,
        連立: &接触点集合の法線と接線の連立,
        有効集合: &法線と接線の連立の有効集合,
    ) {
        let 当て方 = 連立.試験の許容差の当て方();
        self.偽の固有値の下限の取り決め = 当て方.偽の固有値の下限の取り決め();
        for k in 0..self.並び.行の数() {
            let 持ち主 = self.並び.第k行の持ち主(k);
            if let Some(勾配) = 連立.持ち主の行の勾配(持ち主) {
                self.行ごとの解けたと見なす許容差[k] = 当て方.受理の許容差へ掛ける(当て方.行の解けたと見なす許容差(&勾配)).値();
                self.行ごとの基準原点に相対な座標から導く許容差[k] = 勾配.基準原点に相対な座標から導く解けたと見なす許容差().値();
            }
            let 抜き出した行の持ち主::接線の行を持つ点(点の番号) = 持ち主 else {
                continue;
            };
            let Some(接線の行) = 連立.接線の一行を読む(点の番号) else {
                continue;
            };
            self.定数項[k] = (当て方.接線の行の右辺を求める(&接線の行) - 連立.外した点の解放が動かす長さ(接線の行.勾配(), 有効集合)).値();
        }
        self.本番の代わりに置く右辺の捨て方 = match 当て方.右辺の向きを捨てる判定() {
            擬似逆が右辺の向きを捨てる判定の当て方::本番の代わりの規則で捨てる { 捨て方 } => Some(捨て方),
            擬似逆が右辺の向きを捨てる判定の当て方::行ごとの許容差で捨てる
            | 擬似逆が右辺の向きを捨てる判定の当て方::捨てずに真の向きを全部解く
            | 擬似逆が右辺の向きを捨てる判定の当て方::接線の雑音の床へ安全率を掛けた長さで捨てる { .. }
            | 擬似逆が右辺の向きを捨てる判定の当て方::基準原点に相対な座標から導く許容差で捨てる => None,
        };
        self.擬似逆の右辺の判定が比べる行ごとの許容差 = match 当て方.右辺の向きを捨てる判定() {
            擬似逆が右辺の向きを捨てる判定の当て方::行ごとの許容差で捨てる => self.行ごとの解けたと見なす許容差,
            擬似逆が右辺の向きを捨てる判定の当て方::捨てずに真の向きを全部解く => {
                [0.0; 法線と接線の連立の行の上限]
            }
            擬似逆が右辺の向きを捨てる判定の当て方::接線の雑音の床へ安全率を掛けた長さで捨てる {
                長さメートル,
            } => [長さメートル; 法線と接線の連立の行の上限],
            擬似逆が右辺の向きを捨てる判定の当て方::基準原点に相対な座標から導く許容差で捨てる => {
                self.行ごとの基準原点に相対な座標から導く許容差
            }
            // 座標を読まない枝はこの並びを読まない。行ごとの許容差は受理の判定の側だけが使う。
            擬似逆が右辺の向きを捨てる判定の当て方::本番の代わりの規則で捨てる { .. } => {
                self.行ごとの解けたと見なす許容差
            }
        };
    }
}
