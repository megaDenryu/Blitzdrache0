//! 抜き出した連立へ、解けたと見なす許容差の倍率を反映する後処理(Issue #59の数値契約の診断。試験と計器の専用)。
//! 抜き出し(`reduced_system`)から分けているのは、本番の抜き出しが倍率を1度も読まないためである。本番の
//! 組み立ての中へ倍率の分岐を置くと、本番の署名と本番の経路に倍率の型が現れる。ここへ寄せると、本番は
//! 倍率の存在を知らないまま組み立て、試験の構成のときだけこの後処理が値を差し替える。
//! 差し替えるのは2つである。全部の行の解けたと見なす許容差(擬似逆が右辺の固有の向きを捨てるときに比べる値)と、
//! 接線の行の定数項(右辺 −(C_t − δ) の δ)である。法線の隔たりが表現の刻みの内側かどうかの判定には掛けない。
//! あちらは「配置が1ビットも動かない」という表現の事実であり、解法の取り決めではないためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_math::メートル;

use super::active_set::法線と接線の連立の有効集合;
use super::reduced_system::有効な行だけを抜き出した連立;
use super::row_order::抜き出した行の持ち主;
use super::system::接触点集合の法線と接線の連立;

impl 有効な行だけを抜き出した連立 {
    /// 組み立てた行ごとの許容差と、接線の行の定数項へ倍率を反映する。倍率が1倍なら値は1ビットも変わらない。
    pub(super) fn 試験の許容差の倍率を反映する(
        &mut self, 連立: &接触点集合の法線と接線の連立, 有効集合: &法線と接線の連立の有効集合
    ) {
        let 倍率 = 連立.解けたと見なす許容差の倍率();
        for k in 0..self.並び.行の数() {
            self.行ごとの解けたと見なす許容差[k] = 倍率.許容差へ掛ける(メートル::生成する(self.行ごとの解けたと見なす許容差[k])).値();
            let 抜き出した行の持ち主::接線の行を持つ点(点の番号) = self.並び.第k行の持ち主(k) else {
                continue;
            };
            let Some(接線の行) = 連立.接線の一行を読む(点の番号) else {
                continue;
            };
            self.定数項[k] =
                (接線の行.許容差へ倍率を掛けた連立の右辺(倍率) - 連立.外した点の解放が動かす長さ(接線の行.勾配(), 有効集合)).値();
        }
    }
}
