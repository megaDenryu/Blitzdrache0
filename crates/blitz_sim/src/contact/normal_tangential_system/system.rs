//! 接触点集合1つの、法線と接線を同じ対称行列へ入れた連立(判断12・判断13)。この型が持つのは点ごとの2つの行と、
//! 抜き出しが読む口(行の勾配・右辺・外した点の解放の増分)である。解く工程は`subset_search`が持つ。
//! 分けているのは、行を積むのが接触点集合の走査1回であるのに対し、解く工程が有効集合の部分集合ごとに
//! 抜き出しと求解を繰り返す別の局面だからである。
//! 法線の行は非貫通(判断12)がその反復に解くべき右辺 −C_n − α̃ λ_n をそのまま持ち、接線の行は錨の接線変位を零へ
//! 戻す右辺 −(C_t − δ) を持つ。粘着の候補は、この2種類の行を1回の混合連立として同時に解いた解である。
//! 法線を先に確定してから右辺が零の混合連立を足す2段の形にすると、前段の有限回転を後段の線形化が取り消せず、
//! 錨の接線変位が反復のたびに作り直されて接線の乗数が積み増される。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_collision::contact_set::接触点の上限;
use blitz_math::メートル;

use super::super::contact_projection_row::一行の二つの符号付き勾配;
use super::super::non_penetration::非貫通の接触点集合の一行;
use super::active_set::法線と接線の連立の有効集合;
use super::row_order::抜き出した行の持ち主;
use super::tangential_row::錨の接線変位を零へ戻す一行;
use super::tolerance_scale::解けたと見なす許容差の倍率;
use crate::xpbd::ラグランジュ乗数;

/// 接触点集合1つの法線と接線の連立。点ごとに法線の行と接線の行を持ち、どちらも無い点が混ざる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触点集合の法線と接線の連立 {
    点ごとの法線の行: [Option<非貫通の接触点集合の一行>; 接触点の上限],
    点ごとの接線の行: [Option<錨の接線変位を零へ戻す一行>; 接触点の上限],
    点の数: usize,
    解けたと見なす許容差の倍率: 解けたと見なす許容差の倍率,
}

impl 接触点集合の法線と接線の連立 {
    /// 1行も積んでいない連立。
    /// 注意: 点の数が接触点の上限を超える集合は衝突数学層の不変条件の破れであり、添字の範囲外として落ちる。
    pub fn 点の数から空で始める(点の数: usize) -> Self {
        Self::点の数と許容差の倍率から空で始める(点の数, 解けたと見なす許容差の倍率::既定())
    }

    /// 解けたと見なす許容差だけを振った連立。本番は`点の数から空で始める`だけを読み、倍率は常に1倍である。
    pub fn 点の数と許容差の倍率から空で始める(点の数: usize, 倍率: 解けたと見なす許容差の倍率) -> Self {
        Self {
            点ごとの法線の行: [None; 接触点の上限],
            点ごとの接線の行: [None; 接触点の上限],
            点の数,
            解けたと見なす許容差の倍率: 倍率,
        }
    }

    /// この連立が行の許容差へ掛ける倍率。抜き出しと接線の行の組み立てが読む。
    pub fn 解けたと見なす許容差の倍率(&self) -> 解けたと見なす許容差の倍率 {
        self.解けたと見なす許容差の倍率
    }

    pub fn 法線の一行を積む(&mut self, 点の番号: usize, 一行: 非貫通の接触点集合の一行) {
        self.点ごとの法線の行[点の番号] = Some(一行);
    }

    pub fn 接線の一行を積む(&mut self, 点の番号: usize, 一行: 錨の接線変位を零へ戻す一行) {
        self.点ごとの接線の行[点の番号] = Some(一行);
    }

    pub fn 点の数(&self) -> usize {
        self.点の数
    }

    pub fn 法線の一行を読む(&self, 点の番号: usize) -> Option<非貫通の接触点集合の一行> {
        self.点ごとの法線の行[点の番号]
    }

    pub fn 接線の一行を読む(&self, 点の番号: usize) -> Option<錨の接線変位を零へ戻す一行> {
        self.点ごとの接線の行[点の番号]
    }

    /// 有効集合へ入れてよい点の集合。法線の行を持ち、どちらの参加者も動かせないのではない点である。
    /// 部分集合を走査する側は、この集合の部分集合だけを候補にする。
    pub(super) fn 有効集合へ入れてよい点の集合(&self) -> 法線と接線の連立の有効集合 {
        let mut ビット並び = 0;
        for 点の番号 in 0..self.点の数 {
            if self.点ごとの法線の行[点の番号].is_some_and(|一行| !一行.動かせない組か()) {
                ビット並び |= 1u8 << 点の番号;
            }
        }
        法線と接線の連立の有効集合::ビット並びから生成する(ビット並び)
    }

    /// 有効集合から外した点の法線の乗数を零へ解放する増分 −λ_n。法線の行を持たない点は零である。
    pub(super) fn 外した点の法線の乗数を解放する増分(&self, 点の番号: usize) -> ラグランジュ乗数 {
        match self.点ごとの法線の行[点の番号] {
            Some(法線の行) => ラグランジュ乗数::零() - 法線の行.法線のラグランジュ乗数(),
            None => ラグランジュ乗数::零(),
        }
    }

    /// 外した点の解放の増分が、渡した行の右辺の量を動かす長さ Σ_{j∉A} W_ij Δλ_j。抜き出しがこれを右辺から引く。
    pub(super) fn 外した点の解放が動かす長さ(
        &self,
        行の勾配: &一行の二つの符号付き勾配,
        有効集合: &法線と接線の連立の有効集合,
    ) -> メートル {
        let mut 合計 = メートル::生成する(0.0);
        for 点の番号 in (0..self.点の数).filter(|番号| !有効集合.有効か(*番号)) {
            if let Some(法線の行) = self.点ごとの法線の行[点の番号] {
                合計 = 合計 + self.外した点の法線の乗数を解放する増分(点の番号) * 行の勾配.交差の寄与(法線の行.勾配());
            }
        }
        合計
    }

    pub(super) fn 持ち主の行の勾配(&self, 持ち主: 抜き出した行の持ち主) -> Option<一行の二つの符号付き勾配> {
        match 持ち主 {
            抜き出した行の持ち主::法線の行を持つ点(点の番号) => self.点ごとの法線の行[点の番号].map(|一行| *一行.勾配()),
            抜き出した行の持ち主::接線の行を持つ点(点の番号) => self.点ごとの接線の行[点の番号].map(|一行| *一行.勾配()),
        }
    }

    pub(super) fn 持ち主の行の右辺(&self, 持ち主: 抜き出した行の持ち主) -> メートル {
        let 零 = メートル::生成する(0.0);
        match 持ち主 {
            抜き出した行の持ち主::法線の行を持つ点(点の番号) => {
                self.点ごとの法線の行[点の番号].map_or(零, |一行| 一行.連立の右辺())
            }
            抜き出した行の持ち主::接線の行を持つ点(点の番号) => {
                self.点ごとの接線の行[点の番号].map_or(零, |一行| 一行.連立の右辺(self.解けたと見なす許容差の倍率))
            }
        }
    }

    /// 法線の行の対角へ足すコンプライアンスの刻み依存量 α̃。接線の行は硬い位置拘束であるため零である。
    pub(super) fn 持ち主の行の対角へ足す刻み依存量(&self, 持ち主: 抜き出した行の持ち主) -> f32 {
        match 持ち主 {
            抜き出した行の持ち主::法線の行を持つ点(点の番号) => {
                self.点ごとの法線の行[点の番号].map_or(0.0, |一行| 一行.刻み依存量().値())
            }
            抜き出した行の持ち主::接線の行を持つ点(_) => 0.0,
        }
    }
}
