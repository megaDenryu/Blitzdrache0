//! 適用規則が答える、行ごとの解けたと見なす許容差 δ_i と、そこへ受理の倍率を掛ける先(判断13、Issue #59の第4段階)。
//! 適用規則の定義(`tolerance_application.rs`)から分けているのは、あちらが接線の行を積むかと右辺を決める工程であり、
//! こちらが「δ_i をどの座標から採り、受理の倍率をどちらの判定へ掛けるか」だけを答える工程だからである。
//! 触れるフィールドは、許容差の座標の由来(候補(ζ)の軸)・届く先・受理の倍率の3つに限られる。子モジュールに置くのは、
//! 適用規則の私有のフィールドを読む必要があるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::メートル;

use super::super::super::contact_projection_row::一行の二つの符号付き勾配;
use super::super::tolerance_candidate::解けたと見なす許容差を導く座標の由来;
use super::super::tolerance_reach::受理の倍率の届く先;
use super::試験の許容差の当て方;

impl 試験の許容差の当て方 {
    /// この適用規則での、その行の解けたと見なす許容差 δ_i(候補(ζ)の軸で導く座標が変わる)。受理の倍率は掛けない。
    pub fn 行の解けたと見なす許容差(&self, 勾配: &一行の二つの符号付き勾配) -> メートル {
        match self.許容差の座標の由来 {
            解けたと見なす許容差を導く座標の由来::粗い位置の刻みから導く => 勾配.解けたと見なす許容差(),
            解けたと見なす許容差を導く座標の由来::基準原点に相対な座標の刻みから導く => {
                勾配.基準原点に相対な座標から導く解けたと見なす許容差()
            }
        }
    }

    /// 擬似逆が右辺の固有の向きを捨てるときに比べる行ごとの許容差へ、受理の倍率を掛ける。届く先が受理の判定だけなら掛けない。
    pub fn 受理の許容差へ掛ける(&self, 許容差: メートル) -> メートル {
        match self.届く先 {
            受理の倍率の届く先::擬似逆の採否と受理の判定 => self.受理の倍率.許容差へ掛ける(許容差),
            受理の倍率の届く先::受理の判定だけ => 許容差,
        }
    }

    /// 受理の判定(A・B1・B4)が比べる許容差へ掛ける倍率。擬似逆の側で既に掛けた適用規則では掛けない(二重に掛けない)。
    pub fn 受理の判定の許容差へ掛ける(&self, 許容差: メートル) -> メートル {
        match self.届く先 {
            受理の倍率の届く先::擬似逆の採否と受理の判定 => 許容差,
            受理の倍率の届く先::受理の判定だけ => self.受理の倍率.許容差へ掛ける(許容差),
        }
    }
}
