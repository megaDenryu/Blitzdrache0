//! 試験の許容差の当て方を表の見出しへ綴る形(計器の専用)。当て方の定義(`tolerance_application.rs`)から分けているのは、
//! こちらが計器の表のためだけの綴りであり、連立の組み立てが1度も読まないためである。子モジュールに置くのは、当て方の
//! 私有のフィールドを読む必要があるためである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

use super::super::tolerance_candidate::{
    偽の固有値の下限を導く取り決め, 擬似逆が右辺の向きを捨てる判定の当て方, 解けたと見なす許容差を導く座標の由来,
};
use super::super::tolerance_reach::受理の倍率の届く先;
use super::{接線の行への許容差の当て方, 試験の許容差の当て方};

impl 試験の許容差の当て方 {
    /// 表の見出しに綴る形。
    pub fn 綴り(&self) -> String {
        let 右辺 = match self.行への当て方 {
            接線の行への許容差の当て方::右辺へ受理の倍率を掛けて残す => "右辺δ残す",
            接線の行への許容差の当て方::右辺を零にする => "右辺δ零",
            接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする => "内側の行を積まず右辺δ零",
        };
        let 届く先 = match self.届く先 {
            受理の倍率の届く先::擬似逆の採否と受理の判定 => "",
            受理の倍率の届く先::受理の判定だけ => "_倍率は受理の判定だけ",
        };
        let 閾値 = if self.閾値の倍率.比() == 1.0 {
            String::new()
        } else {
            format!("_閾値{}倍", self.閾値の倍率.比())
        };
        let 候補 = match (self.右辺の向きを捨てる判定, self.許容差の座標の由来) {
            (擬似逆が右辺の向きを捨てる判定の当て方::捨てずに真の向きを全部解く, _) => "_候補アルファ".to_owned(),
            (
                擬似逆が右辺の向きを捨てる判定の当て方::接線の雑音の床へ安全率を掛けた長さで捨てる {
                    長さメートル,
                },
                _,
            ) => {
                format!("_候補シータ(δ={長さメートル:.2e})")
            }
            (_, 解けたと見なす許容差を導く座標の由来::基準原点に相対な座標の刻みから導く) => {
                "_候補ゼータ".to_owned()
            }
            _ => String::new(),
        };
        let 下限 = match self.偽の固有値の下限の取り決め {
            偽の固有値の下限を導く取り決め::次数と機械イプシロンから導く => String::new(),
            偽の固有値の下限を導く取り決め::最大の固有値への相対比から導く { 相対比 } => {
                format!("_候補イータ(c={相対比:.2e})")
            }
        };
        format!("受理{}倍_{右辺}{届く先}{閾値}{候補}{下限}", self.受理の倍率.比())
    }
}
