//! 試験の許容差の適用規則から、1つの軸だけを差し替えた別の適用規則を組む口(試験と計器の専用)。
//! 適用規則の定義(`tolerance_application.rs`)から分けているのは、あちらが「この適用規則で連立方程式をどう組むか」を答える
//! 工程であり、こちらが「この適用規則の1つの軸を振った別の適用規則を作る」組み立ての口だからである。計器は、同じ配置へ
//! 軸を1つだけ変えた適用規則を当てて差を読むため、軸ごとに1つの口が要る。子モジュールに置くのは、適用規則の私有の
//! フィールドを書き換える必要があるためである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

use super::super::tolerance_candidate::{偽の固有値の下限を導く取り決め, 擬似逆行列を構成するときに右辺の向きを捨てる判定の適用規則, 解けたと見なす許容差を導く座標の由来};
use super::super::tolerance_reach::{受理の倍率の届く先, 行を積む閾値の倍率};
use super::super::tolerance_scale::解けたと見なす許容差の倍率;
use super::{接線の行への許容差の適用規則, 試験の許容差の適用規則};

impl 試験の許容差の適用規則 {
    /// 旧の形(改訂の前の本番)のまま、右辺の δ と受理の δ に同じ倍率を掛ける。段階A1までの計器と反証(4)(f)の対照が読む。
    pub fn 受理の倍率だけを振る(受理の倍率: 解けたと見なす許容差の倍率) -> Self {
        Self::倍率と行への適用規則から生成する(受理の倍率, 接線の行への許容差の適用規則::全部の拘束行を追加し右辺に受理の倍率を掛けた許容差を残す)
    }

    /// 受理の倍率の届く先だけを差し替えた適用規則。遠方の正接0.58の滑走が擬似逆行列の採否か受理の判定かを分ける計器が読む。
    pub fn 届く先を差し替える(&self, 届く先: 受理の倍率の届く先) -> Self {
        Self { 届く先, ..*self }
    }

    /// 行を積む閾値の倍率だけを差し替えた適用規則。閾値の帯 k δ を測る計器が読む。
    pub fn 行を積む閾値の倍率を差し替える(&self, 閾値の倍率: 行を積む閾値の倍率) -> Self {
        Self { 閾値の倍率, ..*self }
    }

    /// 行への適用規則はそのまま、受理の倍率だけを差し替えた適用規則。同じ配置に別の倍率を当てて採否を比べる計器が読む。
    pub fn 受理の倍率を差し替える(&self, 受理の倍率: 解けたと見なす許容差の倍率) -> Self {
        Self { 受理の倍率, ..*self }
    }

    /// 受理の倍率はそのまま、行への適用規則だけを差し替えた適用規則。同じ配置に別の候補を当てて勝った有効集合を比べる
    /// 計器が読む。
    pub fn 行への適用規則を差し替える(&self, 行への適用規則: 接線の行への許容差の適用規則) -> Self {
        Self { 行への適用規則, ..*self }
    }

    /// 偽の固有値と見なす下限の取り決めだけを差し替えた適用規則(候補(η))。段階A3の計器が読む。
    pub fn 偽の固有値の下限の取り決めを差し替える(&self, 偽の固有値の下限の取り決め: 偽の固有値の下限を導く取り決め) -> Self {
        Self {
            偽の固有値の下限の取り決め, ..*self
        }
    }

    /// 擬似逆行列を構成するときの右辺の判定が比べる許容差だけを差し替えた適用規則(候補(α)と候補(θ))。段階A2と段階A3の計器が読む。
    pub fn 右辺の向きを捨てる判定を差し替える(&self, 右辺の向きを捨てる判定: 擬似逆行列を構成するときに右辺の向きを捨てる判定の適用規則) -> Self {
        Self { 右辺の向きを捨てる判定, ..*self }
    }

    /// 許容差を導く座標の由来だけを差し替えた適用規則(候補(ζ))。段階A2の計器が読む。
    pub fn 許容差の座標の由来を差し替える(&self, 許容差の座標の由来: 解けたと見なす許容差を導く座標の由来) -> Self {
        Self { 許容差の座標の由来, ..*self }
    }
}
