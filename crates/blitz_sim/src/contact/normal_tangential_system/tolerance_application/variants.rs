//! 試験の許容差の当て方から、1つの軸だけを差し替えた別の当て方を組む口(試験と計器の専用)。
//! 当て方の定義(`tolerance_application.rs`)から分けているのは、あちらが「この当て方で連立をどう組むか」を答える
//! 工程であり、こちらが「この当て方の1つの軸を振った別の当て方を作る」組み立ての口だからである。計器は、同じ配置へ
//! 軸を1つだけ変えた当て方を当てて差を読むため、軸ごとに1つの口が要る。子モジュールに置くのは、当て方の私有の
//! フィールドを書き換える必要があるためである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

use super::super::tolerance_candidate::{
    擬似逆が右辺の向きを捨てる判定の当て方, 解けたと見なす許容差を導く座標の由来
};
use super::super::tolerance_reach::{受理の倍率の届く先, 行を積む閾値の倍率};
use super::super::tolerance_scale::解けたと見なす許容差の倍率;
use super::{接線の行への許容差の当て方, 試験の許容差の当て方};

impl 試験の許容差の当て方 {
    /// 旧の形(改訂の前の本番)のまま、右辺の δ と受理の δ に同じ倍率を掛ける。段階A1までの計器と反証(4)(f)の対照が読む。
    pub fn 受理の倍率だけを振る(受理の倍率: 解けたと見なす許容差の倍率) -> Self {
        Self::倍率と行への当て方から生成する(受理の倍率, 接線の行への許容差の当て方::右辺へ受理の倍率を掛けて残す)
    }

    /// 受理の倍率の届く先だけを差し替えた当て方。遠方の正接0.58の滑走が擬似逆の採否か受理の判定かを分ける計器が読む。
    pub fn 届く先を差し替える(&self, 届く先: 受理の倍率の届く先) -> Self {
        Self { 届く先, ..*self }
    }

    /// 行を積む閾値の倍率だけを差し替えた当て方。閾値の帯 k δ を測る計器が読む。
    pub fn 行を積む閾値の倍率を差し替える(&self, 閾値の倍率: 行を積む閾値の倍率) -> Self {
        Self { 閾値の倍率, ..*self }
    }

    /// 行への当て方はそのまま、受理の倍率だけを差し替えた当て方。同じ配置に別の倍率を当てて採否を比べる計器が読む。
    pub fn 受理の倍率を差し替える(&self, 受理の倍率: 解けたと見なす許容差の倍率) -> Self {
        Self { 受理の倍率, ..*self }
    }

    /// 受理の倍率はそのまま、行への当て方だけを差し替えた当て方。同じ配置に別の候補を当てて勝った有効集合を比べる
    /// 計器が読む。
    pub fn 行への当て方を差し替える(&self, 行への当て方: 接線の行への許容差の当て方) -> Self {
        Self { 行への当て方, ..*self }
    }

    /// 擬似逆が右辺の固有の向きを捨てる判定だけを差し替えた当て方(候補(α))。段階A2の計器が読む。
    pub fn 右辺の向きを捨てる判定を差し替える(
        &self, 右辺の向きを捨てる判定: 擬似逆が右辺の向きを捨てる判定の当て方
    ) -> Self {
        Self {
            右辺の向きを捨てる判定,
            ..*self
        }
    }

    /// 許容差を導く座標の由来だけを差し替えた当て方(候補(ζ))。段階A2の計器が読む。
    pub fn 許容差の座標の由来を差し替える(
        &self, 許容差の座標の由来: 解けたと見なす許容差を導く座標の由来
    ) -> Self {
        Self {
            許容差の座標の由来, ..*self
        }
    }
}
