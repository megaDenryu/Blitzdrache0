//! 法線と接線の連立が行の並びに依らないことの検査(判断12・判断13)。担当するのは3つを固定することである。
//! 面と面の4点の順を反転しても剛体へ適用する補正と円錐の判定が読む合力が変わらないこと、4点のどれにも接線の
//! 乗数が載ること、そして接線の力が作る回転を法線の乗数の移し替えが打ち消すことである。
//! 3つ目が、法線の行を同じ連立へ入れたことの検査である。下り側の点の法線の乗数が増え、上り側の点の法線の
//! 乗数が減る形で、接線の力の重心まわりのモーメントを釣り合わせる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use super::solution::接触点集合の法線と接線の同時解;
use super::system_fixture::{四隅の数, 四隅を積んだ連立};
use crate::contact::static_friction::接線のラグランジュ乗数;
use crate::rigid_xpbd::姿勢自由度の補正;

// 四隅を1つの連立として解いた、剛体へ適用する補正の合計と、円錐の判定が読む接線の乗数の合力。
fn 四隅を解いた補正の合計と乗数の合力(順に並べるか: bool) -> (姿勢自由度の補正, 接線のラグランジュ乗数) {
    let 連立 = 四隅を積んだ連立(順に並べるか);
    let 同時解 = 連立.同時に解く();
    let mut 合力 = 接線のラグランジュ乗数::零();
    for 番号 in 0..四隅の数 {
        let Some(一行) = 連立.接線の一行を読む(番号) else {
            panic!("四隅の{番号}番目の接線の行が連立に無い");
        };
        合力 = 合力 + 接線のラグランジュ乗数::零().向きへの増分を足す(一行.接線の向き(), 同時解.一点の接線の乗数の増分(番号));
    }
    (連立.第1の参加者への補正の合計(&同時解), 合力)
}

#[test]
fn 四点の順を反転しても補正と円錐の判定の合力が変わらない() {
    let (順の補正, 順の合力) = 四隅を解いた補正の合計と乗数の合力(true);
    let (逆の補正, 逆の合力) = 四隅を解いた補正の合計と乗数の合力(false);
    let 補正の差 = (順の補正.並進() - 逆の補正.並進()).長さ().値();
    assert!(補正の差 < 1.0e-6, "4点の順を反転すると補正が変わった: {補正の差}");
    let 合力の差 = (順の合力.大きさ().値() - 逆の合力.大きさ().値()).abs();
    assert!(合力の差 < 1.0e-6, "4点の順を反転すると円錐の判定の合力が変わった: {合力の差}");
    assert!(順の合力.大きさ().値() > 0.0, "材料の接線の乗数が零である");
}

#[test]
fn 面と面の四点でも全部の点に接線の乗数が載る() {
    let 同時解 = 四隅を積んだ連立(true).同時に解く();
    for 番号 in 0..四隅の数 {
        let 増分 = 同時解.一点の接線の乗数の増分(番号).値();
        assert!(増分 < 0.0, "四隅の{番号}番目に接線の乗数が載っていない: {増分}");
    }
}

#[test]
fn 接線の力が作る回転を法線の乗数の移し替えが打ち消す() {
    // 材料の接線変位は −x 向きへ戻す向きであり、四隅のうち x が正の2点(番号0と1)へ荷重が移る。
    let 同時解: 接触点集合の法線と接線の同時解 = 四隅を積んだ連立(true).同時に解く();
    let 増える側: f32 = [0, 1].iter().map(|番号| 同時解.一点の法線の乗数の増分(*番号).値()).sum();
    let 減る側: f32 = [2, 3].iter().map(|番号| 同時解.一点の法線の乗数の増分(*番号).値()).sum();
    assert!(増える側 > 0.0, "x が正の側へ法線の荷重が移っていない: {増える側}");
    assert!(減る側 < 0.0, "x が負の側の法線の荷重が減っていない: {減る側}");
    assert!(
        (増える側 + 減る側).abs() < 1.0e-3 * 増える側.abs(),
        "移し替えが法線の乗数の合計を変えている: {増える側} と {減る側}"
    );
}
