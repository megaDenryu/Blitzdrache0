//! 正の量が10の冪の桁ごとに何本居るかを数える度数と、小さい順の並びで最も広い隙間を探す工程(試験と計器の専用)。
//! 固有値の相対値の広がり(`eigen_relative_spread`)と、増分と不確かさの率の広がり(`increment_uncertainty_spread`)の
//! 2つが同じ数え方を要るため、数え方をここへ1つだけ置く。2つの広がりが数える量は桁の範囲が違う(相対値は
//! 1e-8から1e-1、不確かさの率と正規化した増分は1を跨ぐ)ため、いちばん低い桁の下端と桁の本数を持ち主が指定する。
//! 隙間を探す工程を同じファイルへ置くのは、どちらの広がりも「桁ごとに数える」と「閾値を置ける隙間を探す」の2つを
//! 対で使い、片方だけを使う持ち主が無いためである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

/// 正の量を10の冪の桁ごとに数えた度数。
pub(in crate::contact) struct 桁ごとの度数 {
    いちばん低い桁の下端の十の冪: i32,
    度数: Vec<usize>,
}

impl 桁ごとの度数 {
    /// いちばん低い桁の下端を 10^冪 とし、そこから上へ指定の本数だけ桁を並べた度数。第0番はその下端より小さい量、
    /// 最後の番号はその上の全部の量を受ける。
    pub(in crate::contact) fn 範囲から始める(いちばん低い桁の下端の十の冪: i32, 桁の本数: usize) -> Self {
        Self {
            いちばん低い桁の下端の十の冪,
            度数: vec![0; 桁の本数],
        }
    }

    pub(in crate::contact) fn 一つ数える(&mut self, 量: f32) {
        let 番号 = self.桁の番号(量);
        self.度数[番号] += 1;
    }

    /// 表へ綴る形。「1e-8未満:9 1e-8台:13 ...」のように桁の見出しと度数を並べる。
    pub(in crate::contact) fn 綴り(&self) -> String {
        (0..self.度数.len())
            .map(|番号| format!("{}:{}", self.桁の見出し(番号), self.度数[番号]))
            .collect::<Vec<_>>()
            .join(" ")
    }

    fn 桁の番号(&self, 量: f32) -> usize {
        let mut 番号 = 0;
        let mut 桁の下端 = 10.0_f32.powi(self.いちばん低い桁の下端の十の冪);
        while 番号 + 1 < self.度数.len() && 量 >= 桁の下端 {
            番号 += 1;
            桁の下端 *= 10.0;
        }
        番号
    }

    fn 桁の見出し(&self, 番号: usize) -> String {
        let 冪 = self.いちばん低い桁の下端の十の冪 + i32::try_from(番号).unwrap_or(0) - 1;
        if 番号 == 0 {
            format!("1e{}未満", self.いちばん低い桁の下端の十の冪)
        } else {
            format!("1e{冪}台")
        }
    }
}

/// 小さい順に並んだ正の量の列で、隣どうしの比が最も大きい組。並びが2つ未満なら無しである。
pub(in crate::contact) fn 最も広い隙間を探す(小さい順の並び: &[f32]) -> Option<(f32, f32)> {
    小さい順の並び
        .windows(2)
        .filter(|組| 組[0] > 0.0)
        .max_by(|左, 右| (左[1] / 左[0]).total_cmp(&(右[1] / 右[0])))
        .map(|組| (組[0], 組[1]))
}
