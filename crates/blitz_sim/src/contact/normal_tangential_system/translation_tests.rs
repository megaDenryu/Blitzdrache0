//! 同じ4点の場面を世界の中で平行移動したときの連立の解の検査(判断12・判断13)。担当するのは2つを固定することである。
//! 法線と接線のどちらにも直交する軸へ100万メートル動かしても点ごとの増分が原点の付近と一致すること、そして
//! 法線の軸へ100万メートル動かしたときに、その軸の表現の刻みを収束の限界として乗数が増え続けないことである。
//! 直交する軸は接線の解ける固有の向きと無関係であり、そこを動かして解が変わるなら、捨てる向きの判定が行の方向でなく
//! 世界位置の座標の大きさそのものを読んでいる。法線の軸は逆に刻みが粗くなる軸であり、そこでは法線の行が解けなくなる。
//! 解けない行に対して増分を積み続けないことが、乗数が増え続けないことの意味である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 変位};

use super::system_fixture::{四隅の数, 平行移動して四隅を積んだ連立};

const 遠くまでの長さ: f32 = 1.0e6;
// 材料の法線はy軸、接線変位はx軸である。z軸はそのどちらにも直交する。
fn 世界の変位(x: f32, y: f32, z: f32) -> 変位<ワールド> {
    変位::成分から生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

// 平行移動した四隅の連立を解いた、点ごとの接線と法線の乗数の増分。
fn 平行移動して解いた増分(平行移動: 変位<ワールド>) -> ([f32; 四隅の数], [f32; 四隅の数]) {
    let 同時解 = 平行移動して四隅を積んだ連立(true, 平行移動).同時に解く().定まった解を取り出す();
    let mut 接線 = [0.0; 四隅の数];
    let mut 法線 = [0.0; 四隅の数];
    for 番号 in 0..四隅の数 {
        接線[番号] = 同時解.一点の接線の乗数の増分(番号).値();
        法線[番号] = 同時解.一点の法線の乗数の増分(番号).値();
    }
    (接線, 法線)
}

#[test]
fn 法線と接線に直交する軸へ遠くまで平行移動しても乗数の増分が変わらない() {
    let (原点の接線, 原点の法線) = 平行移動して解いた増分(世界の変位(0.0, 0.0, 0.0));
    let (遠くの接線, 遠くの法線) = 平行移動して解いた増分(世界の変位(0.0, 0.0, 遠くまでの長さ));
    for 番号 in 0..四隅の数 {
        assert!(原点の接線[番号].abs() > 0.0, "原点の付近で{番号}番目に接線の増分が載っていない");
        let 接線の差 = (遠くの接線[番号] - 原点の接線[番号]).abs() / 原点の接線[番号].abs();
        assert!(
            接線の差 < 1.0e-3,
            "直交する軸へ{遠くまでの長さ}メートル動かすと{番号}番目の接線の増分が{}から{}へ変わった",
            原点の接線[番号],
            遠くの接線[番号]
        );
        let 法線の差 = (遠くの法線[番号] - 原点の法線[番号]).abs() / 原点の法線[番号].abs();
        assert!(
            法線の差 < 1.0e-3,
            "直交する軸へ{遠くまでの長さ}メートル動かすと{番号}番目の法線の増分が{}から{}へ変わった",
            原点の法線[番号],
            遠くの法線[番号]
        );
    }
}

#[test]
fn 法線の軸へ遠くまで平行移動しても法線の乗数が刻みを超えて積まれない() {
    // y = 100万メートルの表現の刻みは0.0625メートルであり、法線の行の右辺を解けたと見なす許容差がこの大きさになる。
    // 法線の増分がその刻みを有効逆質量で割った量を超えるなら、解けない行に対して乗数を積んでいる。
    let 刻み = メートル::生成する(遠くまでの長さ).表現の刻み幅().値();
    let (接線, 法線) = 平行移動して解いた増分(世界の変位(0.0, 遠くまでの長さ, 0.0));
    for 番号 in 0..四隅の数 {
        assert!(
            法線[番号].abs() <= 刻み,
            "法線の軸へ動かした場面で{番号}番目の法線の増分{}が刻み{刻み}を超えた",
            法線[番号]
        );
        assert!(接線[番号] < 0.0, "法線の軸へ動かすと{番号}番目の接線の増分が消えた: {}", 接線[番号]);
    }
}
