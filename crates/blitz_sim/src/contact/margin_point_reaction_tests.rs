//! 接触生成の余白の内側で離れている接触解法の候補点が、接触拘束になっても力を出さないことの縦の検査(判断11・12・13)。
//! 担当するのは、`blitz_collision` の問い合わせが返した負の符号付き貫通量の候補点を実際の剛体どうしの接触拘束へ写し、
//! 非貫通の射影が `離れている` を返して法線のラグランジュ乗数も補正も動かさないことと、その点が静止摩擦の仮の射影で
//! `法線反力が無い` を返すことを固定することである。
//! `blitz_collision` 側の検査は接触点の数だけを見るため、余白の点が解法へ渡った後に何もしないことはそこでは固定できない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11」「判断12」「判断13」。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::batch_builder::接触拘束のバッチの組み立て;
use super::body_body_contact::剛体と剛体の接触拘束;
use super::contact_test_fixtures::{
    世界の位置を作る, 動的な参加者を作る, 単一の材質の混合則, 台帳へ登録する, 形の位置を作る, 接触に参加する剛体を作る,
    直方体どうしの接触点集合を求める, 直方体を作る, 試験の刻み幅,
};
use super::non_penetration::非貫通の一回の射影の結果;
use super::static_friction::静止摩擦の一回の仮の射影の結果;
use crate::rigid_body::{剛体の台帳, 姿勢, 配置};
use crate::xpbd::{コンプライアンス, ラグランジュ乗数};

const 半分の長さ: f32 = 0.5;
const 食い込み: f32 = 0.001;
// 0.5 sin(傾き) = 食い込み の境目(0.115度)を超え、食い込み + 接触生成の余白 の境目(0.688度)には届かない傾き。
// この傾きでは、上の箱の底面の4つの角のうち2つが参照面の平面より外側へ出て、余白の内側の候補点として残る。
const 余白の内側に角が残る傾きの度: f32 = 0.3;

fn 上の箱の姿勢() -> 姿勢 {
    let 半角 = 余白の内側に角が残る傾きの度.to_radians() / 2.0;
    姿勢::生成する(0.0, 0.0, 半角.sin(), 半角.cos()).unwrap()
}

fn 上下の箱の配置() -> (配置, 配置) {
    (
        配置::生成する(世界の位置を作る(0.0, 半分の長さ - 食い込み, 0.0), 上の箱の姿勢()),
        配置::生成する(世界の位置を作る(0.0, -半分の長さ, 0.0), 姿勢::恒等()),
    )
}

// 上下の箱の接触点集合から剛体どうしの接触拘束を組み、余白の内側で離れている点だけを取り出す。
fn 余白の内側で離れている拘束を集める() -> Vec<剛体と剛体の接触拘束> {
    let (上の配置, 下の配置) = 上下の箱の配置();
    let 集合 = 直方体どうしの接触点集合を求める(
        &直方体を作る(形の位置を作る(0.0, 半分の長さ - 食い込み, 0.0), 上の箱の姿勢(), 半分の長さ),
        &直方体を作る(形の位置を作る(0.0, -半分の長さ, 0.0), 姿勢::恒等(), 半分の長さ),
    );
    let mut 台帳 = 剛体の台帳::空();
    let 上 = 接触に参加する剛体を作る(台帳へ登録する(&mut 台帳, 上の配置), 上の配置);
    let 下 = 接触に参加する剛体を作る(台帳へ登録する(&mut 台帳, 下の配置), 下の配置);
    let 混合則 = 単一の材質の混合則();
    let mut 組み立て = 接触拘束のバッチの組み立て::生成する(&混合則, コンプライアンス::硬い(), 試験の刻み幅(), 1);
    組み立て.剛体どうしの接触点集合を積む(&上, &下, &集合).unwrap();
    組み立て
        .二つのバッチを組み立てる()
        .剛体どうしの接触拘束()
        .iter()
        .filter(|拘束| 拘束.引数().生成時の符号付き貫通量.長さ() < メートル::生成する(0.0))
        .copied()
        .collect()
}

#[test]
fn 余白の内側で離れている候補点が接触拘束として実在する() {
    assert!(
        !余白の内側で離れている拘束を集める().is_empty(),
        "傾き{余白の内側に角が残る傾きの度}度・食い込み{食い込み}メートルで負の符号付き貫通量の拘束が1つも作られていない"
    );
}

#[test]
fn 余白の内側で離れている接触拘束は非貫通の射影で補正も乗数も生まない() {
    let (上の配置, 下の配置) = 上下の箱の配置();
    let (上の参加者, 下の参加者) = (動的な参加者を作る(上の配置, 1.0, 1.0), 動的な参加者を作る(下の配置, 1.0, 1.0));
    for mut 拘束 in 余白の内側で離れている拘束を集める() {
        let 結果 = 拘束.一回射影する(&上の参加者, &下の参加者);
        assert_eq!(結果, 非貫通の一回の射影の結果::離れている, "余白の内側の点が押し戻しを起こした");
        assert_eq!(
            拘束.法線のラグランジュ乗数(),
            ラグランジュ乗数::零(),
            "余白の内側の点が法線の乗数を積んだ"
        );
    }
}

#[test]
fn 法線反力の無い余白の点は静止摩擦にも参加しない() {
    let (上の配置, 下の配置) = 上下の箱の配置();
    let (上の参加者, 下の参加者) = (動的な参加者を作る(上の配置, 1.0, 1.0), 動的な参加者を作る(下の配置, 1.0, 1.0));
    for mut 拘束 in 余白の内側で離れている拘束を集める() {
        拘束.一回射影する(&上の参加者, &下の参加者);
        assert_eq!(
            拘束.静止摩擦を一回仮に射影する(&上の参加者, &下の参加者),
            静止摩擦の一回の仮の射影の結果::法線反力が無い,
            "法線反力の無い余白の点が静止摩擦へ参加した"
        );
    }
}
