//! 混合則: 材質の識別子から表面物性を引く表と、材質対ごとに接触物性を上書きする表を持ち、接触1つの接触物性を決める型(判断15)。
//! 既定則(摩擦は相乗平均・反発は最大値)には物理的な正当性が無く挙動の既定値であるため、対ごとの上書きの口を最初から置く。
//! 上書きが登録されていればその値を返し、登録されていなければ既定則で混ぜる。どちらの経路も引数の順で結果が変わらない。
//! 表面物性が登録されていない材質の識別子は型付きエラーで拒み、黙って既定の物性を当てない。
//! 組み立ては `混合則の組み立て` が担い、この型は組み立てを終えた後は書き換わらない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断15: 接触物性は両表面の物性から混合則で決め、既定則と材質対の上書き表を持つ」

use std::collections::BTreeMap;

use super::contact_property::接触物性;
use super::material_id::材質の識別子;
use super::material_pair::材質の対;
use super::property_error::接触物性エラー;
use super::surface_property::表面物性;

/// 2つの材質の識別子から接触1つの接触物性を決める規則。接触拘束の生成だけがこれを読む。
#[derive(Debug, Clone, PartialEq)]
pub struct 混合則 {
    表面物性の表: BTreeMap<材質の識別子, 表面物性>,
    上書き表: BTreeMap<材質の対, 接触物性>,
}

impl 混合則 {
    // 組み立てが検査を終えた2つの表を受ける唯一の入口。
    pub(super) fn 検査済みの表から組む(
        表面物性の表: BTreeMap<材質の識別子, 表面物性>, 上書き表: BTreeMap<材質の対, 接触物性>
    ) -> Self {
        Self {
            表面物性の表, 上書き表
        }
    }

    /// 2つの材質の接触物性。上書き表に対が在ればその値、無ければ両表面物性の既定則の混合である。
    /// どちらの材質も表面物性が登録されていなければならない(上書きが在っても、材質の実在を先に課す)。
    pub fn 接触物性を求める(
        &self, 第1の材質: 材質の識別子, 第2の材質: 材質の識別子
    ) -> Result<接触物性, 接触物性エラー> {
        let 第1の表面物性 = self.表面物性を引く(第1の材質)?;
        let 第2の表面物性 = self.表面物性を引く(第2の材質)?;
        if let Some(上書き) = self.上書き表.get(&材質の対::生成する(第1の材質, 第2の材質)) {
            return Ok(*上書き);
        }
        Ok(第1の表面物性.既定則で接触物性を求める(第2の表面物性))
    }

    /// 材質の識別子に登録された表面物性。開発用の計器と検査が値を確かめるために読む。
    pub fn 表面物性を引く(&self, 材質: 材質の識別子) -> Result<&表面物性, 接触物性エラー> {
        self.表面物性の表.get(&材質).ok_or(接触物性エラー::材質の表面物性が未登録 {
            材質の識別子: 材質.値()
        })
    }
}
