//! 接触点集合1つがバッチの中で占める範囲(判断11・判断13)。組み立てが接触点集合を1つ積むたびに1件できる。
//! 静止摩擦のクーロン円錐の判定を接触点集合の単位で行うため、細分の反復はこの範囲で拘束を区切って借りる。
//! 開始の添字と接触点の数で持つのは、組み立てが積み終えた時点で確定する2つがこれだからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

/// 接触点集合1つがバッチの一覧の中で占める範囲。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触点集合の占める範囲 {
    開始の添字: usize,
    接触点の数: usize,
}

impl 接触点集合の占める範囲 {
    // 積み終えた時点の開始の添字と接触点の数から作る。組み立てだけがこれを作る。
    pub(super) fn 生成する(開始の添字: usize, 接触点の数: usize) -> Self {
        Self {
            開始の添字, 接触点の数
        }
    }

    /// この接触点集合の最初の接触点がバッチの一覧の何番目にあるか。
    pub fn 開始の添字(&self) -> usize {
        self.開始の添字
    }

    /// この接触点集合に属する接触点の数。
    pub fn 接触点の数(&self) -> usize {
        self.接触点の数
    }

    // バッチの一覧をこの範囲で切り出すための、終わりの1つ後ろの添字。
    pub(super) fn 終わりの添字(&self) -> usize {
        self.開始の添字 + self.接触点の数
    }
}
