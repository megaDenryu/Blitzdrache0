//! 混合則の組み立て: 表面物性の登録と材質対の上書きの登録を受け、両方が揃ってから成立する不変条件を検査して混合則を作る型(判断15)。
//! 組み立てを分けているのは、上書きの対が実在する材質を指しているかを、表面物性の登録がすべて済むまで判定できないためである。
//! 登録の順に依らず同じ混合則になるよう、対の実在の検査は組み立ての最後に1度だけ行う。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断15: 接触物性は両表面の物性から混合則で決め、既定則と材質対の上書き表を持つ」

use std::collections::BTreeMap;
use std::collections::btree_map::Entry;

use super::contact_property::接触物性;
use super::material_id::材質の識別子;
use super::material_pair::材質の対;
use super::mixing_rule::混合則;
use super::property_error::接触物性エラー;
use super::surface_property::表面物性;

/// 混合則を作るための積み上げ。二重登録はその場で拒み(先に登録した値は残す)、対の材質の実在は組み立てで拒む。
#[derive(Debug, Clone, Default, PartialEq)]
pub struct 混合則の組み立て {
    表面物性の表: BTreeMap<材質の識別子, 表面物性>,
    上書き表: BTreeMap<材質の対, 接触物性>,
}

impl 混合則の組み立て {
    /// 表面物性も上書きも1つも持たない積み上げ。
    pub fn 生成する() -> Self {
        Self::default()
    }

    /// 材質の識別子へ表面物性を結び付ける。同じ識別子を2回登録すると、どちらが正しいかを決められないため拒む。
    /// 空いているときだけ挿入するのは、拒む登録が先の値を置き換えたまま呼び出し側へエラーを返さないためである。
    pub fn 表面物性を登録する(&mut self, 材質: 材質の識別子, 表面物性: 表面物性) -> Result<(), 接触物性エラー> {
        let Entry::Vacant(空き) = self.表面物性の表.entry(材質) else {
            return Err(接触物性エラー::表面物性の二重登録 {
                材質の識別子: 材質.値()
            });
        };
        空き.insert(表面物性);
        Ok(())
    }

    /// 材質の対の接触物性を既定則より優先する値として登録する。対は昇順へ正規化されるため、順を入れ替えた2回目も二重登録である。
    pub fn 材質対の上書きを登録する(
        &mut self,
        第1の材質: 材質の識別子,
        第2の材質: 材質の識別子,
        接触物性: 接触物性,
    ) -> Result<(), 接触物性エラー> {
        let 対 = 材質の対::生成する(第1の材質, 第2の材質);
        let Entry::Vacant(空き) = self.上書き表.entry(対) else {
            return Err(接触物性エラー::材質対の上書きの二重登録 {
                小さい方: 対.小さい方().値(),
                大きい方: 対.大きい方().値(),
            });
        };
        空き.insert(接触物性);
        Ok(())
    }

    /// 上書きの対がどちらも登録済みの材質を指していることを確かめて混合則にする。指していなければ型付きエラーで拒む。
    pub fn 組み立てる(self) -> Result<混合則, 接触物性エラー> {
        for 対 in self.上書き表.keys() {
            for 材質 in [対.小さい方(), 対.大きい方()] {
                if !self.表面物性の表.contains_key(&材質) {
                    return Err(接触物性エラー::材質の表面物性が未登録 {
                        材質の識別子: 材質.値()
                    });
                }
            }
        }
        Ok(混合則::検査済みの表から組む(self.表面物性の表, self.上書き表))
    }
}
