//! 粘着の候補が相補条件とクーロン円錐を同時に満たすことの検査(判断12・判断13)。単体の材料は2つである。
//! 1つ目は、初めの食い込みが残っている坂の1細分目である。混合の連立が貫通の解消と接線の補正を1度に決めるため、
//! この細分で集合が滑走中へ落ちてはならない。法線を先に確定してから接線を足す2段の形では、前段の非貫通が作った
//! 接線変位を後段がもう一度払うことになり、この細分で円錐を超えた。
//! 2つ目は、保持している最中に接触点集合の1点が離れる細分である。離れた点は法線の有効集合から外れ、その点の
//! 接線の乗数を支える法線反力が無くなる。残る3点だけで相補条件と円錐を満たさなければならない。
//! この2つが、傾きの正接が静止摩擦係数より小さい坂で集合が滑走へ落ちた2つの起こり方そのものである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use super::super::friction_coefficient::摩擦係数;
use super::residual_separation::場面の残差の分離;
use super::slope_fixture::坂の場面を組む;
use super::slope_geometry::坂の場面の条件;
use super::static_friction_method::場面の静止摩擦の解き方;
use super::sticking_candidate_fixture::{一点が離れた四隅の接触点集合, 平らな床の場面と予測, 離れる点の番号};
use crate::xpbd::ラグランジュ乗数;

// 円錐の内側に収まる滑り。3点の法線の乗数が食い込み1e-5から積まれるのに対し、接線の変位はその1割である。
const 円錐の内側に収まる滑らせる長さ: f32 = 1.0e-6;
const 面と面の接触点の数: usize = 4;

#[test]
fn 初めの食い込みが残る一細分目でも粘着の候補が滑走へ落ちない() {
    let mut 場面 = 坂の場面を組む(&坂の場面の条件 {
        傾きの正接: 0.50,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
        残差の分離: 場面の残差の分離::残差の変化を速度から除く,
    });
    場面.一細分進める();
    let 観測 = 場面.直前の細分の観測;
    assert_eq!(観測.接触点の数, 面と面の接触点の数, "1細分目が面と面の4点になっていない");
    assert_eq!(場面.粘着の候補が解けなかった接触点集合の延べ数, 0, "1細分目の粘着の候補が解けなかった");
    assert_eq!(観測.滑走中の接触点の数, 0, "初めの食い込みを解く1細分目で集合が滑走中へ落ちた");
    assert!(
        観測.法線の乗数の合計 > ラグランジュ乗数::零(),
        "1細分目に法線の乗数が積まれていない: {:?}",
        観測.法線の乗数の合計
    );
}

#[test]
fn 保持中に一点が離れる細分でも粘着の候補が相補条件と円錐を満たす() {
    let (場面, 予測) = 平らな床の場面と予測();
    let mut 接触点集合 = 一点が離れた四隅の接触点集合(&場面, &予測, 円錐の内側に収まる滑らせる長さ, 0.0);
    let 結果 = 場面.接触点集合の粘着の候補を解く(&mut 接触点集合, 予測);
    assert_eq!(
        結果.粘着の候補が解けなかった接触点集合の数, 0,
        "1点が離れた集合の粘着の候補が解けなかった"
    );
    for (番号, 拘束) in 接触点集合.iter().enumerate() {
        assert!(!拘束.静止摩擦の解の状態().滑走中か(), "1点が離れただけで{番号}番目が滑走中へ落ちた");
        assert!(
            拘束.法線のラグランジュ乗数() >= ラグランジュ乗数::零(),
            "{番号}番目の法線の乗数が負になった: {:?}",
            拘束.法線のラグランジュ乗数()
        );
    }
    assert_eq!(
        接触点集合[離れる点の番号].法線のラグランジュ乗数(),
        ラグランジュ乗数::零(),
        "離れた点に法線反力が残った"
    );
}
