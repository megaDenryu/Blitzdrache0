//! 底面の四隅に接触点と錨を置いた4点の接触点集合を組むことである。四隅のうち3点は食い込ませ、1点は離す。
//! 「保持している最中に接触点集合の1点が離れる細分」がこの材料であり、混合の連立が扱わなければならない状態遷移
