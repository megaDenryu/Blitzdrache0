/// 水平な床の上の箱の場面と、その1細分目の予測。接触点集合の材料はこの予測の配置に置く。
pub(super) fn 平らな床の場面と予測() -> (一つの箱と静的な直方体の場面, 予測の状態) {
    let 場面 = 坂の場面を組む(&坂の場面の条件 {
        傾きの正接: 0.0,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(材料の静止摩擦係数).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.4).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
        残差の分離: 場面の残差の分離::残差の変化を速度から除く,
    });
    let (_, 予測, _) = 場面
        .予測器
        .動的剛体を予測する(&場面.箱の配置, &場面.箱の運動状態, &場面.箱の質量特性, &一刻みの入力::無し());
    (場面, 予測)
}

/// 底面の四隅のうち3点が食い込み、1点が離れた接触点集合。食い込む3点は法線の乗数を1回の射影で積んである。
/// 錨は接触点からx軸の向きへ`滑らせる長さ`だけずらして置き、離れた点にだけ古い接線の乗数を持たせる。
pub(super) fn 一点が離れた四隅の接触点集合(
    場面: &一つの箱と静的な直方体の場面,
    予測: &予測の状態,
    滑らせる長さ: f32,
    離れた点の古い接線の乗数: f32,
) -> Vec<剛体と静的世界の接触拘束> {
    let 参加者 = 姿勢自由度の参加者::動的(*予測.配置(), &場面.箱の質量特性);
    (0..四隅の数)
        .map(|番号| {
            let 隔たり = if 番号 == 離れる点の番号 {
                離れる隔たり
            } else {
                食い込む隔たり
            };
            let mut 拘束 = 一つの隅の拘束(予測, 四隅の局所点(番号), 隔たり, 滑らせる長さ);
            拘束.一回射影する(&参加者);
            if 番号 == 離れる点の番号 {
                拘束.静止摩擦の仮の乗数を確定する(x軸の接線の乗数(離れた点の古い接線の乗数));
            }
            拘束
        })
        .collect()
}

// x軸の向きの接線のラグランジュ乗数。離れた点へ古い乗数を持たせるために読む。
fn x軸の接線の乗数(大きさ: f32) -> 接線のラグランジュ乗数 {
    接線のラグランジュ乗数::零().向きへの増分を足す(x軸(), ラグランジュ乗数::有効逆質量で割った長さから生成する(大きさ))
}

fn x軸() -> 方向<ワールド> {
    方向::生成する(1.0, 0.0, 0.0).unwrap()
}

fn 四隅の局所点(番号: usize) -> 変位<ローカル> {
    let 符号 = |立っているか: bool| {
        if 立っているか {
            底面の半分の長さ
        } else {
            -底面の半分の長さ
        }
    };
    変位::成分から生成する(
        メートル::生成する(符号(番号 & 1 == 0)),
        メートル::生成する(-底面の半分の長さ),
        メートル::生成する(符号(番号 & 2 == 0)),
    )
}

// 接触法線は剛体から静的世界へ向かう下向きであり、静的世界側の接触点は剛体の接触点から法線の向きへ隔たりだけ、
// 接平面のx軸の向きへ滑らせる長さだけ動かした点である。隔たりが負なら食い込みである。
fn 一つの隅の拘束(
    予測: &予測の状態, 局所点: 変位<ローカル>, 隔たり: f32, 滑らせる長さ: f32
) -> 剛体と静的世界の接触拘束 {
    let 基本 = 剛体と静的世界の基本の引数();
    let 剛体の接触点 = 予測.配置().局所点の世界位置(局所点);
    let 静的世界側の接触点 = 剛体の接触点.変位を足す(変位::成分から生成する(
        メートル::生成する(滑らせる長さ),
        メートル::生成する(-隔たり),
        メートル::生成する(0.0),
    ));
    剛体と静的世界の接触拘束::引数と刻み幅から生成する(
        剛体と静的世界の接触拘束の引数 {
            剛体側の局所接触点: 局所点,
            静的世界側の接触点,
            ..基本
        },
        試験の刻み幅(),
    )
    .unwrap()
}
