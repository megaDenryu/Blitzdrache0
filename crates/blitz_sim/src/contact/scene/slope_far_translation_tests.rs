//! 刻みが2倍になる平行移動と正接0.58を重ねた敵対の反例(判断13の2026-09-12の実装の細目の反証(4)(b)。Issue #59の
//! 第4段階)。本番の当て方は δ を接線の行を積むかどうかの閾値に使う。世界の原点から遠い場面では δ が大きくなるため、
//! 必要な接線の行まで丸ごと落として集合が滑走へ落ちる可能性がある。この試験はそれを刺す。
//! 固定するのは2つである。受理の倍率0.5倍・1倍・2倍で保持と滑走の分類が変わらないこと。行を積むかどうかの閾値を
//! 持たない候補(i)(全部の点の行を積み右辺を −C_t)の分類と、本番の当て方の分類が一致すること(一致しなければ、
//! 分類の違いは行を落としたことに由来する)。0.58 を完了の境界へ昇格しない。この試験は保持そのものを要求しない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::super::friction_coefficient::摩擦係数;
use super::super::normal_tangential_system::{
    接線の行への許容差の当て方, 解けたと見なす許容差の倍率, 試験の許容差の当て方
};
use super::slope_fixture::{一刻みの細分数, 坂の場面を移動と許容差の当て方で組む};
use super::slope_geometry::坂の場面の条件;
use super::slope_holding::坂の箱の保持と滑走;
use super::static_friction_method::場面の静止摩擦の解き方;

const 保持を見る刻み数: usize = 600;
const 敵対の傾きの正接: f32 = 0.58;
// 坂の中心から接触点までの長さ。これだけ法線の向きへ動かすと接触点の座標が2倍になり、表現の刻みが2倍になる。
const 刻みを二倍にする長さ: f32 = 20.4999;
const 振る受理の倍率: &[f32] = &[0.5, 1.0, 2.0];

fn 敵対の条件() -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接: 敵対の傾きの正接,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    }
}

fn 遠方で分類する(当て方: 試験の許容差の当て方) -> 坂の箱の保持と滑走 {
    let 条件 = 敵対の条件();
    let mut 場面 = 坂の場面を移動と許容差の当て方で組む(&条件, メートル::生成する(刻みを二倍にする長さ), 当て方);
    let 初めの重心 = 場面.箱の配置.重心の位置();
    場面.細分を進める(保持を見る刻み数 * 一刻みの細分数);
    坂の箱の保持と滑走::場面から決める(&場面, 初めの重心, &条件)
}

#[test]
fn 刻み二倍の平行移動と正接零点五八で受理の倍率を振っても分類が変わらない() {
    let 基準 = 遠方で分類する(試験の許容差の当て方::本番と同じ当て方());
    for &受理の倍率 in 振る受理の倍率 {
        let 当て方 = 試験の許容差の当て方::本番と同じ当て方()
            .受理の倍率を差し替える(解けたと見なす許容差の倍率::比から生成する(受理の倍率));
        assert_eq!(
            遠方で分類する(当て方),
            基準,
            "受理{受理の倍率}倍で遠方の正接{敵対の傾きの正接}の分類が1倍と違う"
        );
    }
}

#[test]
fn 刻み二倍の平行移動と正接零点五八で行を落としても行を落とさない候補と分類が一致する() {
    let 行を落とさない候補 = 試験の許容差の当て方::倍率と行への当て方から生成する(
        解けたと見なす許容差の倍率::既定で生成する(),
        接線の行への許容差の当て方::右辺を零にする,
    );
    assert_eq!(
        遠方で分類する(試験の許容差の当て方::本番と同じ当て方()),
        遠方で分類する(行を落とさない候補),
        "遠方の正接{敵対の傾きの正接}で、δ の内側の行を落とす本番と落とさない候補(i)の分類が違う。落とした行が分類を変えた"
    );
}
