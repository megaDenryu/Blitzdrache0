//! 場面の反復1回の結果(判断19の反復の試験専用の実装)。担当するのは、進めた予測と、有効集合の組み替えが巡回して
//! 混合の補正を適用できなかった接触点集合の数を一緒に運ぶことである。
//! 反復を回す工程(`substep_solve`)から分けているのは、こちらが工程の返す値の形であり、あちらが値を作る工程だからである。
//! 数を運ぶのは、組み替えの巡回を無言で捨てないためである。場面はこれを細分ごとに延べ数へ足し、検査が零であることを固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use crate::rigid_xpbd::予測の状態;

/// 反復1回、あるいは接触点集合1つを解いた結果。
pub(super) struct 一回の反復の結果 {
    pub(super) 予測: 予測の状態,
    pub(super) 有効集合の組み替えが巡回した接触点集合の数: usize,
}

impl 一回の反復の結果 {
    /// 巡回が起きなかった結果。
    pub(super) fn 巡回なしで生成する(予測: 予測の状態) -> Self {
        Self {
            予測,
            有効集合の組み替えが巡回した接触点集合の数: 0,
        }
    }

    /// 接触点集合1つが巡回した結果。混合の補正は適用せず、射影の前の予測をそのまま運ぶ。
    pub(super) fn 一つの接触点集合が巡回したとして生成する(予測: 予測の状態) -> Self {
        Self {
            予測,
            有効集合の組み替えが巡回した接触点集合の数: 1,
        }
    }

    /// 続く接触点集合の結果を足し込む。予測は後の結果のものを採り、巡回の数は積み上げる。
    pub(super) fn 次の結果を足す(self, 次: Self) -> Self {
        Self {
            予測: 次.予測,
            有効集合の組み替えが巡回した接触点集合の数: self.有効集合の組み替えが巡回した接触点集合の数
                + 次.有効集合の組み替えが巡回した接触点集合の数,
        }
    }
}
