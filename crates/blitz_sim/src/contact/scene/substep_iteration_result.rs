//! 場面の反復1回の結果(判断19の反復の試験専用の実装)。担当するのは、進めた予測と、粘着の候補が解けなかった
//! 接触点集合の数を一緒に運ぶことである。
//! 反復を回す工程(`substep_solve`)から分けているのは、こちらが工程の返す値の形であり、あちらが値を作る工程だからである。
//! 解いた回数も一緒に運ぶのは、走査の費用が接触点集合ごとに決まり、細分の外からは数え直せないためである。
//! 解けなかった連立方程式の読み取りも一緒に運ぶのは、解けなかった中身が解いた工程の中にしか無く、外からは組み直せないためである。
//! 数を運ぶのは、解けなかった集合を無言で捨てないためである。場面はこれを細分ごとに延べ数へ足し、検査が零であることを固定する。
//! 数える対象は、相補条件を満たす有効集合が無かった集合と、表現の精度が不足した集合と、混合連立方程式の受理の判定で数値の
//! 契約を破った集合の3つであり、精度の不足の数だけを別に運ぶ(段階A2の計器が解けなかった理由を分けて読む。受理の破れは
//! 解けなかった連立方程式の読み取りの結末の綴りが理由を持つ)。円錐を超えて滑走へ移った集合は数えない。あちらは解けた結果として滑走を選んだのであり、解けなかったのではない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::unsolved_system_reading::解けなかった連立方程式の読み取り;
use crate::contact::normal_tangential_system::部分集合を解いた回数;
use crate::rigid_xpbd::予測の状態;

/// 反復1回、あるいは接触点集合1つを解いた結果。
pub(super) struct 一回の反復の結果 {
    pub(super) 予測: 予測の状態,
    pub(super) 粘着の候補が解けなかった接触点集合の数: usize,
    pub(super) 表現の精度が不足した接触点集合の数: usize, // 解けなかった数の内訳。残りは相補条件を満たす有効集合が無かった数である
    pub(super) 解いた回数: 部分集合を解いた回数,          // 有効集合の探索がこの結果を出すあいだに解いた連立方程式の回数
    pub(super) 解けなかった連立方程式: Vec<解けなかった連立方程式の読み取り>, // 解けなかった集合1つにつき1件。解けた反復では空である
}

impl 一回の反復の結果 {
    /// 粘着の候補が解けなかった集合が無かった結果。
    pub(super) fn 解けなかった集合を含まずに生成する(予測: 予測の状態) -> Self {
        Self {
            予測,
            粘着の候補が解けなかった接触点集合の数: 0,
            表現の精度が不足した接触点集合の数: 0,
            解いた回数: 部分集合を解いた回数::零(),
            解けなかった連立方程式: Vec::new(),
        }
    }

    /// 接触点集合1つに相補条件を満たす有効集合が無かった結果。混合の補正は適用せず、法線だけを解いた予測を運ぶ。
    pub(super) fn 相補条件を満たす有効集合が無かったとして生成する(
        予測: 予測の状態,
        読み取り: 解けなかった連立方程式の読み取り,
    ) -> Self {
        Self {
            予測,
            粘着の候補が解けなかった接触点集合の数: 1,
            表現の精度が不足した接触点集合の数: 0,
            解いた回数: 部分集合を解いた回数::零(),
            解けなかった連立方程式: vec![読み取り],
        }
    }

    /// 接触点集合1つが表現の精度の不足で解けなかった結果。混合の補正は適用せず、法線だけを解いた予測を運ぶ。
    pub(super) fn 表現の精度が不足したとして生成する(
        予測: 予測の状態, 読み取り: 解けなかった連立方程式の読み取り
    ) -> Self {
        Self {
            予測,
            粘着の候補が解けなかった接触点集合の数: 1,
            表現の精度が不足した接触点集合の数: 1,
            解いた回数: 部分集合を解いた回数::零(),
            解けなかった連立方程式: vec![読み取り],
        }
    }

    /// 接触点集合1つが混合連立方程式の受理の判定で数値の契約を破った結果(退避の枝)。混合の補正は適用せず、法線だけを解いた予測を運ぶ。
    pub(super) fn 受理の契約を破ったとして生成する(
        予測: 予測の状態, 読み取り: 解けなかった連立方程式の読み取り
    ) -> Self {
        Self {
            予測,
            粘着の候補が解けなかった接触点集合の数: 1,
            表現の精度が不足した接触点集合の数: 0,
            解いた回数: 部分集合を解いた回数::零(),
            解けなかった連立方程式: vec![読み取り],
        }
    }

    /// この結果を出すあいだに有効集合の探索が解いた連立方程式の回数を添える。走査の費用を読む計器のための口である。
    pub(super) fn 解いた回数を添える(self, 解いた回数: 部分集合を解いた回数) -> Self {
        Self { 解いた回数, ..self }
    }

    /// 続く接触点集合の結果を足し込む。予測は後の結果のものを採り、解けなかった数は積み上げる。
    pub(super) fn 次の結果を足す(mut self, 次: Self) -> Self {
        let mut 解けなかった連立方程式 = std::mem::take(&mut self.解けなかった連立方程式);
        解けなかった連立方程式.extend(次.解けなかった連立方程式);
        Self {
            解けなかった連立方程式,
            予測: 次.予測,
            粘着の候補が解けなかった接触点集合の数: self.粘着の候補が解けなかった接触点集合の数
                + 次.粘着の候補が解けなかった接触点集合の数,
            表現の精度が不足した接触点集合の数: self.表現の精度が不足した接触点集合の数 + 次.表現の精度が不足した接触点集合の数,
            解いた回数: self.解いた回数.足す(次.解いた回数),
        }
    }
}
