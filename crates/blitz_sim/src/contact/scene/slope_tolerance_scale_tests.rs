//! 受理の許容差の倍率を0.5倍と2倍に振っても、坂の箱の保持と滑走の分類が変わらないことの試験(判断13の2026-09-12の
//! 実装の細目の反証(4)(a)。Issue #59の第4段階)。倍率1倍の9組は `slope_tests` が固定し、この試験は0.5倍と2倍の
//! 18組を足して27組にする。担当するのは、静止摩擦係数0.6の坂で正接0.50と0.55の箱が鉛直軸まわりの回し0度・30度・
//! 45度の3方向とも600刻みで保持し、正接0.61が3方向とも滑走することを、受理の倍率0.5倍と2倍で固定することである。
//! 許容差は「数値上解けたと見なす」取り決めであって物理の目標ではないため、その倍率が物理の分類を動かしてはならない。
//! 世界座標を動かさずに許容差だけを振るのは、座標の表せる細かさを同時に変えないためである(座標を動かす形は
//! `tolerance_boundary_tests` が持つ)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use std::f32::consts::PI;

use blitz_math::メートル;

use super::super::friction_coefficient::摩擦係数;
use super::super::normal_tangential_system::{解けたと見なす許容差の倍率, 試験の許容差の適用規則};
use super::slope_fixture::{一刻みの細分数, 坂の場面を移動と許容差の適用規則で組む};
use super::slope_geometry::坂の場面の条件;
use super::slope_holding::坂の箱の保持と滑走;
use super::static_friction_method::場面の静止摩擦の解き方;

const 保持を見る刻み数: usize = 600;
const 三方向の回し: &[f32] = &[0.0, PI / 6.0, PI / 4.0];
const 保持を要求する傾きの正接: [f32; 2] = [0.50, 0.55];
const 滑走を要求する傾きの正接: f32 = 0.61;

fn 傾きの条件(傾きの正接: f32, 鉛直軸まわりの回し: f32) -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接,
        鉛直軸まわりの回し,
        静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    }
}

// 本番の適用規則のまま受理の倍率だけを差し替えて600刻み進めた分類。
fn 受理の倍率で分類する(条件: &坂の場面の条件, 受理の倍率: f32) -> 坂の箱の保持と滑走 {
    let 適用規則 = 試験の許容差の適用規則::本番と同じ適用規則()
        .受理の倍率を差し替える(解けたと見なす許容差の倍率::比から生成する(受理の倍率));
    let mut 場面 = 坂の場面を移動と許容差の適用規則で組む(条件, メートル::生成する(0.0), 適用規則);
    let 初めの重心 = 場面.箱の配置.重心の位置();
    場面.細分を進める(保持を見る刻み数 * 一刻みの細分数);
    場面.保持と滑走を分類する(初めの重心, 条件)
}

fn 九組の分類を固定する(受理の倍率: f32) {
    for &回し in 三方向の回し {
        for 正接 in 保持を要求する傾きの正接 {
            assert_eq!(
                受理の倍率で分類する(&傾きの条件(正接, 回し), 受理の倍率),
                坂の箱の保持と滑走::保持,
                "受理{受理の倍率}倍・回し{回し}・正接{正接}の箱が保持しない"
            );
        }
        assert_eq!(
            受理の倍率で分類する(&傾きの条件(滑走を要求する傾きの正接, 回し), 受理の倍率),
            坂の箱の保持と滑走::滑走,
            "受理{受理の倍率}倍・回し{回し}・正接{滑走を要求する傾きの正接}の箱が滑走しない"
        );
    }
}

