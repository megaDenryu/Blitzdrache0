//! 水平な床へ落とした箱で判断14の反発の定量の基準を固定する試験。担当するのは2つである。
//! 跳ね返りの高さが e² h と相対誤差3パーセント以内で一致すること、反発係数0.8の箱を静置しても3600刻みで跳ねないことである。
//! 静置の側が要るのは、低速の反発の抑制(|v_n⁻| ≤ v_閾値 なら e = 0)が無いと、重力由来の微小な接近速度を衝突と
//! 誤認して箱が毎刻み微小に跳ねるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

#![allow(clippy::unwrap_used)]

use blitz_math::{キログラム, メートル, メートル毎秒毎秒, 秒, 速度};

use super::super::friction_coefficient::摩擦係数;
use super::super::normal_tangential_system::解けたと見なす許容差の倍率;
use super::super::restitution_coefficient::反発係数;
use super::super::solver_quality::接触を解く品質の設定;
use super::super::surface_property::表面物性;
use super::scene_geometry::世界の位置;
use super::scene_settings::場面の設定;
use super::static_friction_method::場面の静止摩擦の解き方;
use super::substep_harness::一つの箱と静的な直方体の場面;
use crate::constraint_graph::一様な加速度;
use crate::rigid_body::{姿勢, 配置};
use crate::xpbd::刻み幅;

const 箱の半分の長さの値: f32 = 0.5;
const 床の半分の長さの値: f32 = 5.0;
const 静置の食い込み: f32 = 0.0001;
const 落とす高さ: f32 = 1.0;
const 試験の反発係数: f32 = 0.8;
const 一刻みの細分数: usize = 8;
const 位置の反復回数: u32 = 2; // 由来は正本の判断19の実装の細目
const 速度段階の巡回数: u32 = 4;
const 落下と跳ね返りを見る細分数: usize = 1200; // 1メートルの落下(0.45秒)と e²h までの上昇(0.36秒)を覆う長さ

// 床の上面を高さ0に置き、箱の重心を指定の隙間だけ上へ置く。摩擦は跳ね返りに関わらないため零にする。
fn 落下の場面を組む(初めの隙間: f32) -> 一つの箱と静的な直方体の場面 {
    一つの箱と静的な直方体の場面::生成する(&場面の設定 {
        箱の半分の長さ: メートル::生成する(箱の半分の長さの値),
        箱の質量: キログラム::生成する(1.0).unwrap(),
        箱の配置: 配置::生成する(世界の位置(0.0, 箱の半分の長さの値 + 初めの隙間, 0.0), 姿勢::恒等()),
        箱の初速: 速度::零(),
        静的な直方体の配置: 配置::生成する(世界の位置(0.0, -床の半分の長さの値, 0.0), 姿勢::恒等()),
        静的な直方体の半分の長さ: メートル::生成する(床の半分の長さの値),
        表面物性: 表面物性::生成する(摩擦係数::零(), 摩擦係数::零(), 反発係数::生成する(試験の反発係数).unwrap()).unwrap(),
        重力: 一様な加速度::成分から生成する(
            メートル毎秒毎秒::生成する(0.0),
            メートル毎秒毎秒::生成する(-9.81),
            メートル毎秒毎秒::生成する(0.0),
        ),
        細分の刻み幅: 刻み幅::生成する(秒::生成する(1.0 / 480.0)).unwrap(),
        解く品質: 接触を解く品質の設定::生成する(位置の反復回数, 速度段階の巡回数).unwrap(),
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
        解けたと見なす許容差の倍率: 解けたと見なす許容差の倍率::既定で生成する(),
    })
}

impl 一つの箱と静的な直方体の場面 {
    // 床の上面と箱の底面の隙間。床の上面を高さ0に置くこの試験の場面でだけ意味を持つため、この試験のモジュールに置く。
    fn 床からの隙間(&self) -> f32 {
        self.箱の重心の高さ().値() - 箱の半分の長さの値
    }
}

fn 跳ね返りの高さを測る() -> f32 {
    let mut 場面 = 落下の場面を組む(落とす高さ);
    let mut 床に触れた = false;
    let mut 跳ね返りの高さ: f32 = 0.0;
    for _ in 0..落下と跳ね返りを見る細分数 {
        場面.一細分進める();
        if 場面.直前の細分の観測.接触点の数 > 0 {
            床に触れた = true;
        } else if 床に触れた {
            跳ね返りの高さ = 跳ね返りの高さ.max(場面.床からの隙間());
        }
    }
    assert!(床に触れた, "箱が床に触れていない");
    跳ね返りの高さ
}

#[test]
fn 落とした箱の跳ね返りの高さは反発係数の二乗を掛けた高さになる() {
    let 跳ね返りの高さ = 跳ね返りの高さを測る();
    let 解析の高さ = 試験の反発係数 * 試験の反発係数 * 落とす高さ;
    let 相対誤差 = (跳ね返りの高さ - 解析の高さ).abs() / 解析の高さ;
    assert!(
        相対誤差 <= 0.03,
        "跳ね返りの高さが e²h と3パーセント以上ずれた(測定{跳ね返りの高さ}、解析{解析の高さ})"
    );
}

fn 静置の最も高い隙間を測る() -> f32 {
    let mut 場面 = 落下の場面を組む(-静置の食い込み);
    let mut 最も高い隙間: f32 = f32::MIN;
    for _ in 0..3600 * 一刻みの細分数 {
        場面.一細分進める();
        最も高い隙間 = 最も高い隙間.max(場面.床からの隙間());
    }
    最も高い隙間
}

#[test]
fn 反発係数が高い箱を静置しても三千六百刻みで跳ねない() {
    let 最も高い隙間 = 静置の最も高い隙間を測る();
    assert!(最も高い隙間 <= 1.0e-4, "静置した箱が跳ねた(最も高い隙間{最も高い隙間}メートル)");
}
