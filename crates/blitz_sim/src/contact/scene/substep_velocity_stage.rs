//! 場面の速度段階の巡回(判断14の試験専用の実装)。1巡目で動摩擦と反発を、2巡目からは反発だけを適用する。
//! 位置の反復(`substep_solve`)から分けているのは、こちらが細分の終わりに1度だけ呼ばれ、配置を読むだけで書かないためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::メートル毎秒;

use super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::super::contact_batches::接触拘束の二つのバッチ;
use super::super::velocity_stage::{接触の速度段階の結果, 速度段階の接触点の条件};
use super::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_body::運動状態;
use crate::rigid_xpbd::姿勢自由度の参加者;

impl 一つの箱と静的な直方体の場面 {
    // 判断14の速度段階。1巡目で動摩擦と反発を、2巡目からは反発だけを適用する。面と面の接触では点を1巡しただけでは
    // 法線の条件が同時に揃わず、偽の回転が残るためである(動摩擦は1細分に1度だけ与える量なので巡回しない)。
    pub(super) fn 速度段階を適用する(
        &self,
        バッチ: &接触拘束の二つのバッチ,
        予測の前の法線相対速度: &[メートル毎秒],
        再構成した運動状態: 運動状態,
    ) -> 運動状態 {
        let 参加者 = 姿勢自由度の参加者::動的(self.箱の配置, &self.箱の質量特性);
        let mut 運動状態 = 再構成した運動状態;
        for 巡 in 0..self.速度段階の巡回数 {
            for (拘束, 法線相対速度) in バッチ.剛体と静的世界の接触拘束().iter().zip(予測の前の法線相対速度) {
                if !拘束.法線反力が在るか() {
                    continue;
                }
                let a = 拘束.速度段階の剛体の参加点(&参加者, 運動状態);
                let b = 拘束.速度段階の静的世界の参加点();
                let 条件 = self.速度段階の条件を組む(拘束, *法線相対速度);
                let 結果 = if 巡 == 0 {
                    self.速度段階.一点へ適用する(a, b, 条件)
                } else {
                    self.速度段階.一点へ反発だけ適用する(a, b, 条件)
                };
                if let 接触の速度段階の結果::衝撃を適用した {
                    適用後のaの運動状態,
                ..
                } = 結果
                {
                    運動状態 = 適用後のaの運動状態;
                }
            }
        }
        運動状態
    }

    // 反証のときだけ滑走中の印を立て直す。反証は静止摩擦の射影を飛ばすため、印を立てる者が居なくなる。
    fn 速度段階の条件を組む(
        &self, 拘束: &剛体と静的世界の接触拘束, 法線相対速度: メートル毎秒
    ) -> 速度段階の接触点の条件 {
        if self.静止摩擦の位置拘束を外すか {
            return 速度段階の接触点の条件::生成する(
                拘束.引数().接触法線,
                拘束.引数().接触物性,
                拘束.法線のラグランジュ乗数(),
                法線相対速度,
                true,
            );
        }
        拘束.速度段階の条件を組む(法線相対速度)
    }
}
