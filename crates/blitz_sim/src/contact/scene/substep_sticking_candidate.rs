//! 場面の細分の中の粘着の候補(判断12・判断13の接触点集合の単位の試験専用の実装)。担当するのは、接触点集合1つの
//! 法線の行と接線の行を1回の混合連立方程式として同時に解き、混合連立方程式の受理の判定(数値の契約4つと円錐)を通った解だけを配置と
//! 法線の乗数と接線の乗数へ一括で確定することである。数値の契約を破った解は退避の枝(法線だけの連立方程式)へ落とす。
//! 法線を先に確定してから右辺が零の混合連立方程式を足す2段の形にしないのは、前段の非貫通が作った接線変位を後段が
//! もう一度払うことになり、接線の乗数が反復のたびに積み増されるためである。この形なら、初めの食い込みを解く過渡と、
//! 保持中に法線の有効な点が減る細分の両方を同じ相補問題の中で扱える。
//! 円錐を超えたときと、粘着の候補が解けなかったときの後始末は`substep_sliding_fallback`が持つ。行を積む工程は
//! `substep_sticking_rows`が持つ。どちらもこの工程とは別の局面である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::super::normal_tangential_system::{混合連立方程式の受理の結果, 相補条件を満たす有効集合を探した結末};
use super::substep_harness::一つの箱と静的な直方体の場面;
use super::substep_iteration_result::一回の反復の結果;
use super::unsolved_system_reading::解けなかった連立方程式の読み取り;
use crate::rigid_xpbd::{予測の状態, 姿勢自由度の参加者};

impl 一つの箱と静的な直方体の場面 {
    /// 接触点集合1つの粘着の候補を1回の混合連立方程式で解く。円錐の内側なら配置・法線の乗数・接線の乗数を一括で確定し、
    /// 超えたときと解けなかったときは同じ開始の配置から法線だけの連立方程式を解き直す。
    pub(super) fn 接触点集合の粘着の候補を解く(
        &self,
        接触点集合: &mut [剛体と静的世界の接触拘束],
        射影の前の予測: 予測の状態,
    ) -> 一回の反復の結果 {
        let Some(先頭) = 接触点集合.first() else {
            return 一回の反復の結果::解けなかった集合を含まずに生成する(射影の前の予測);
        };
        if 先頭.静止摩擦の解の状態().滑走中か() {
            return 一回の反復の結果::解けなかった集合を含まずに生成する(
                self.接触点集合の非貫通を同時に解く(接触点集合, 射影の前の予測),
            );
        }
        let 接触物性 = 先頭.引数().接触物性;
        let 参加者 = 姿勢自由度の参加者::動的(*射影の前の予測.配置(), &self.箱の質量特性);
        let (連立方程式, 点を入れた結果) = self.法線と接線の連立方程式を組む(接触点集合, &参加者);
        let (結末, 解いた回数) = 連立方程式.相補条件を満たす有効集合で同時に解いて解いた回数も返す();
        let (同時解, 受理の材料) = match 結末 {
            相補条件を満たす有効集合を探した結末::有効集合が定まった { 同時解, 受理の材料 } => {
                (同時解, 受理の材料)
            }
            相補条件を満たす有効集合を探した結末::相補条件を満たす有効集合が無い => {
                return 一回の反復の結果::相補条件を満たす有効集合が無かったとして生成する(
                    self.接触点集合の非貫通を同時に解く(接触点集合, 射影の前の予測),
                    解けなかった連立方程式の読み取り::連立方程式と結末から読む(
                        &連立方程式,
                        "相補条件を満たす有効集合が無い",
                    ),
                )
                .解いた回数を添える(解いた回数);
            }
            相補条件を満たす有効集合を探した結末::表現の精度が不足した => {
                return 一回の反復の結果::表現の精度が不足したとして生成する(
                    self.接触点集合の非貫通を同時に解く(接触点集合, 射影の前の予測),
                    解けなかった連立方程式の読み取り::連立方程式と結末から読む(&連立方程式, "表現の精度が不足した"),
                )
                .解いた回数を添える(解いた回数);
            }
        };
        let 仮の乗数 = self.仮の乗数の集まりを求める(接触点集合, &連立方程式, &同時解, &点を入れた結果);
        match 受理の材料.円錐の判定を記して判定する(仮の乗数.円錐の内側か(接触物性)) {
            混合連立方程式の受理の結果::受理した => {}
            混合連立方程式の受理の結果::円錐を超えた => {
                return 一回の反復の結果::解けなかった集合を含まずに生成する(self.粘着の候補を捨てて滑走中にする(
                    接触点集合,
                    射影の前の予測,
                    &仮の乗数,
                ))
                .解いた回数を添える(解いた回数);
            }
            混合連立方程式の受理の結果::数値の契約を破った(理由) => {
                return 一回の反復の結果::受理の契約を破ったとして生成する(
                    self.接触点集合の非貫通を同時に解く(接触点集合, 射影の前の予測),
                    解けなかった連立方程式の読み取り::連立方程式と受理の破れから読む(&連立方程式, &理由),
                )
                .解いた回数を添える(解いた回数);
            }
        }
        for (添字, 拘束) in 接触点集合.iter_mut().enumerate() {
            拘束.法線と接線の連立方程式の法線の乗数の増分を取り込む(&参加者, 同時解.一点の法線の乗数の増分(添字));
            拘束.静止摩擦の仮の乗数を確定する(仮の乗数.一点の仮の接線の乗数(添字).確定する接線の乗数());
        }
        一回の反復の結果::解けなかった集合を含まずに生成する(
            射影の前の予測.補正を適用する(&連立方程式.第1の参加者への補正の合計(&同時解)),
        )
        .解いた回数を添える(解いた回数)
    }
}
