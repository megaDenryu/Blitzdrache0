//! 場面の細分の終わりに接線の残差を測り、その変化を打ち消す仮の補正を求める工程(判断24の試験専用の実装)。
//! 反復の工程(`substep_solve`)から分けているのは、あちらが反復のたびに配置を書き換える局面であるのに対し、
//! こちらが反復を終えた確定の配置で1度だけ測り、配置を1ビットも書かない局面だからである。
//! 反証の枝は、残差を測るところまでは同じに行い、仮の補正だけを零に固定する。履歴が持ち越す値を反証の側でも
//! 同じに保ち、比べる差が速度の経路だけになるようにするためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

#![cfg(test)]

use super::super::contact_batches::接触拘束の二つのバッチ;
use super::super::static_friction::残差の変化を打ち消す仮の補正の連立;
use super::residual_separation::場面の残差の分離;
use super::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_xpbd::{予測の状態, 姿勢自由度の参加者, 姿勢自由度の補正};

impl 一つの箱と静的な直方体の場面 {
    /// 反復を終えた配置で全部の接触点の残差を測り、残差がこの細分で動いた量を打ち消す仮の補正を返す。
    /// 返した補正を配置へ適用してはならない。速度の再構成だけがこれを読む。
    pub(super) fn 細分の終わりの残差から仮の補正を求める(
        &self,
        バッチ: &mut 接触拘束の二つのバッチ,
        予測: &予測の状態,
    ) -> 姿勢自由度の補正 {
        let 参加者 = 姿勢自由度の参加者::動的(*予測.配置(), &self.箱の質量特性);
        for 拘束 in バッチ.剛体と静的世界の接触拘束を反復のために借りる().iter_mut() {
            拘束.細分の終わりの接線の残差を測る(&参加者);
        }
        if self.残差の分離 == 場面の残差の分離::残差の変化を速度へ運ばせる {
            return 姿勢自由度の補正::零();
        }
        let mut 合計 = 姿勢自由度の補正::零();
        for 集合番号 in 0..バッチ.剛体と静的世界の接触点集合の数() {
            let mut 連立 = 残差の変化を打ち消す仮の補正の連立::空で始める();
            for 拘束 in バッチ.剛体と静的世界の接触点集合を反復のために借りる(集合番号).iter() {
                拘束.残差の変化を仮の補正の連立へ積む(&mut 連立, &参加者);
            }
            合計 = 合計.合わせる(&連立.二つの参加者への仮の補正を求める().0);
        }
        合計
    }
}
