//! 同じ1細分の中で、位置の反復を重ねるごとに法線の乗数の合計と最大の食い込みがどこへ寄るかを記録する計器(判断12)。
//! 担当するのは、静止摩擦の位置拘束を外した坂の場面を落ち着かせてから、1本の細分を32反復まで回し、各反復の後の
//! Σλ_n と最大の食い込みを綴ることである。`normal_multiplier_sum_tests`が測るのは別々の長時間の場面の細分の末の
//! 平均であり、反復の途中の収束ではない。この計器はその収束そのものを見る。合否は判定しない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::super::friction_coefficient::摩擦係数;
use super::slope_fixture::{一刻みの細分数, 坂の場面を組む};
use super::slope_geometry::{坂の場面の条件, 重力の大きさ};
use super::static_friction_method::場面の静止摩擦の解き方;
use super::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_body::一刻みの入力;

const 測る傾きの正接: f32 = 0.9;
const 落ち着くまでの刻み数: usize = 8;
const 記録する反復回数: u32 = 32;

fn 測る条件() -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接: 測る傾きの正接,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の解き方: 場面の静止摩擦の解き方::静止摩擦の位置拘束を外す,
    }
}

// 細分1本あたりの法線力積の解析値 m g cosθ h²。質量1キログラム、細分の刻み幅は1/480秒である。
fn 法線の乗数の合計の解析値() -> f32 {
    let 余弦 = 1.0 / (1.0 + 測る傾きの正接 * 測る傾きの正接).sqrt();
    let 刻み幅 = 1.0 / 480.0;
    重力の大きさ * 余弦 * 刻み幅 * 刻み幅
}

impl 一つの箱と静的な直方体の場面 {
    // 次の1細分の位置の反復を、各反復の後の Σλ_n と最大の食い込みを綴りながら回す。細分の結果は場面へ書き戻さない。
    fn 一細分の法線の反復を記録する(&mut self, 反復回数: u32) {
        let (前の状態, mut 予測, _) =
            self.予測器
                .動的剛体を予測する(&self.箱の配置, &self.箱の運動状態, &self.箱の質量特性, &一刻みの入力::無し());
        let mut バッチ = self.接触拘束のバッチを組む(&予測);
        let _ = self.履歴の記録を引き継ぐ(&mut バッチ, &前の状態.保存した配置());
        let 解析値 = 法線の乗数の合計の解析値();
        for 反復番号 in 1..=反復回数 {
            for 集合の番号 in 0..バッチ.剛体と静的世界の接触点集合の数() {
                let 接触点集合 = バッチ.剛体と静的世界の接触点集合を反復のために借りる(集合の番号);
                予測 = self.接触点集合の非貫通を同時に解く(接触点集合, 予測);
            }
            let 合計: f32 = バッチ
                .剛体と静的世界の接触拘束()
                .iter()
                .map(|拘束| 拘束.法線のラグランジュ乗数().値())
                .sum();
            println!(
                "反復{反復番号} Σλ_n={合計:.6e} 解析値との差={:.4}% 最大の食い込み={:.6e}",
                (合計 - 解析値) / 解析値 * 100.0,
                self.反復を終えた最大の食い込み(&バッチ, &予測).値(),
            );
            let 参加者 = crate::rigid_xpbd::姿勢自由度の参加者::動的(*予測.配置(), &self.箱の質量特性);
            for (番号, 拘束) in バッチ.剛体と静的世界の接触拘束().iter().enumerate() {
                println!(
                    "  点{番号} C_n={:.6e} λ_n={:.6e} 上限={:.6e}",
                    拘束.同時解法の一行にする(&参加者).隔たり().値(),
                    拘束.法線のラグランジュ乗数().値(),
                    拘束.同時解法の一行にする(&参加者).乗数の上限().値(),
                );
            }
        }
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 一細分の中の法線の反復の収束を記録する() {
    let mut 場面 = 坂の場面を組む(&測る条件());
    場面.細分を進める(落ち着くまでの刻み数 * 一刻みの細分数);
    println!("解析値={:.6e}", 法線の乗数の合計の解析値());
    場面.一細分の法線の反復を記録する(記録する反復回数);
}
