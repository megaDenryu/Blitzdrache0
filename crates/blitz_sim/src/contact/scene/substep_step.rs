impl 一つの箱と静的な直方体の場面 {
    pub(super) fn 一細分進める(&mut self) {
        let (前の状態, mut 予測, 予測の運動状態) =
            self.予測器
                .動的剛体を予測する(&self.箱の配置, &self.箱の運動状態, &self.箱の質量特性, &一刻みの入力::無し());
        let mut バッチ = self.接触拘束のバッチを組む(&予測);
        let 開始した接触点の数 = self.履歴の記録を引き継ぐ(&mut バッチ, &前の状態.保存した配置());
        let 予測の前の法線相対速度 = self.予測の前の法線相対速度を測る(&バッチ, &予測, 予測の運動状態);
        for _ in 0..self.解く品質.位置の反復回数() {
            let 結果 = self.一回反復する(&mut バッチ, 予測);
            self.粘着の候補が解けなかった接触点集合の延べ数 += 結果.粘着の候補が解けなかった接触点集合の数;
            予測 = 結果.予測;
        }
        self.錨を置き直した細分を数える(&バッチ);
        let 仮の補正 = self.細分の終わりの残差から仮の補正を求める(&mut バッチ, &予測);
        let 補正を引く前 = 前の状態.確定した配置から速度を再構成する(予測.配置(), self.刻み幅);
        let 再構成した運動状態 = 前の状態.確定した配置と仮の補正から速度を再構成する(予測.配置(), &仮の補正, self.刻み幅);
        self.箱の配置 = *予測.配置();
        self.箱の運動状態 = self.速度段階を適用する(&バッチ, &予測の前の法線相対速度, 再構成した運動状態);
        self.直前の細分の観測 = self.細分の観測を作る(&バッチ, &予測, 開始した接触点の数, 補正を引く前.並進速度());
        let 終わりの項目: Vec<_> = バッチ
            .剛体と静的世界の接触拘束()
            .iter()
            .map(剛体と静的世界の接触拘束::細分の終わりの履歴の項目)
            .collect();
        self.履歴.細分の終わりの記録で置き換える(&終わりの項目).unwrap();
    }

    // 反復を終えた配置で最も深い食い込み。隔たりが正の点しか無ければ零である。
    pub(super) fn 反復を終えた最大の食い込み(
        &self, バッチ: &接触拘束の二つのバッチ, 予測: &予測の状態
    ) -> メートル {
        let 参加者 = 姿勢自由度の参加者::動的(*予測.配置(), &self.箱の質量特性);
        let 最も深い = バッチ
            .剛体と静的世界の接触拘束()
            .iter()
            .map(|拘束| -拘束.同時解法の一行にする(&参加者).隔たり().値())
            .fold(0.0, f32::max);
        メートル::生成する(最も深い)
    }

    pub(super) fn 接触拘束のバッチを組む(&self, 予測: &予測の状態) -> 接触拘束の二つのバッチ {
        let 剛体 = 接触に参加する剛体::生成する(
            self.箱の識別子,
            *予測.配置(),
            材質の識別子::生成する(場面の材質),
            形の最小の厚み::生成する(self.箱の半分の長さ * 2.0).unwrap(),
        );
        let mut 組み立て = 接触拘束のバッチの組み立て::生成する(&self.混合則, コンプライアンス::硬い(), self.刻み幅, 1);
        if let Some(集合) = self.接触点集合を求める(予測) {
            組み立て.剛体と静的世界の接触点集合を積む(&剛体, &self.静的世界の接触相手, &集合).unwrap();
        }
        let mut バッチ = 組み立て.二つのバッチを組み立てる();
        バッチ.鍵の昇順へ並べ替える();
        バッチ
    }

    fn 接触点集合を求める(&self, 予測: &予測の状態) -> Option<接触点集合<直方体どうしの接触の特徴の対>> {
        let 箱 = 直方体を組む(予測.配置(), self.箱の半分の長さ);
        let 箱の運動 = 接触生成の余白を導く形の運動::動く形から生成する(&箱, self.箱の運動状態);
        let 静的な形の運動 = 接触生成の余白を導く形の運動::静止した形から生成する(&self.静的な直方体);
        let 長さ = 細分の運動から接触点集合の生成が読む長さを導く(&箱の運動, &静的な形の運動, self.刻み幅).unwrap();
        let 問い = 長さ.直方体どうしの問い合わせを組む(&箱, &self.静的な直方体);
        match 問い.二つの直方体の重なりの接触点集合を求める().unwrap() {
            二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) => Some(集合),
            二つの直方体の重なりの接触点集合::二つの直方体は離れている => None,
        }
    }
}
