//! 場面の細分1本の工程(判断19の順序の試験専用の実装)。予測 → 接触点集合 → 履歴の併走 → 反復(接触点集合ごとの非貫通の同時解法 → 静止摩擦)
//! → 速度と角速度の再構成 → 速度段階、の順で1本進める。細分ごとに呼ばれるため、場面の生成と読み出しから分けている。
//! 索引の更新と候補の列挙は、この場面が対を1つしか持たないため要らない(本物の工程は後続の作業が組む)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::scene_settings::細分の観測;
use super::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_body::一刻みの入力;
use crate::rigid_xpbd::{予測の状態, 姿勢自由度の参加者};
use crate::xpbd::ラグランジュ乗数;
use blitz_math::メートル;

impl 一つの箱と静的な直方体の場面 {
    pub(super) fn 一細分進める(&mut self) {
        let (前の状態, mut 予測, 予測の運動状態) =
            self.予測器
                .動的剛体を予測する(&self.箱の配置, &self.箱の運動状態, &self.箱の質量特性, &一刻みの入力::無し());
        let mut バッチ = self.接触拘束のバッチを組む(&予測);
        let 開始した接触点の数 = self.履歴の記録を引き継ぐ(&mut バッチ, &前の状態.保存した配置());
        let 予測の前の法線相対速度 = self.予測の前の法線相対速度を測る(&バッチ, &予測, 予測の運動状態);
        for _ in 0..self.解く品質.位置の反復回数() {
            let 結果 = self.一回反復する(&mut バッチ, 予測);
            self.粘着の候補が解けなかった接触点集合の延べ数 += 結果.粘着の候補が解けなかった接触点集合の数;
            予測 = 結果.予測;
        }
        let 再構成した運動状態 = 前の状態.確定した配置から速度を再構成する(予測.配置(), self.刻み幅);
        self.箱の配置 = *予測.配置();
        self.箱の運動状態 = self.速度段階を適用する(&バッチ, &予測の前の法線相対速度, 再構成した運動状態);
        self.直前の細分の観測 = 細分の観測 {
            接触点の数: バッチ.剛体と静的世界の接触拘束().len(),
            開始した接触点の数,
            滑走中の接触点の数: バッチ
                .剛体と静的世界の接触拘束()
                .iter()
                .filter(|拘束| 拘束.静止摩擦の解の状態().滑走中か())
                .count(),
            法線の乗数の合計: バッチ
                .剛体と静的世界の接触拘束()
                .iter()
                .fold(ラグランジュ乗数::零(), |合計, 拘束| 合計 + 拘束.法線のラグランジュ乗数()),
            最大の食い込み: self.反復を終えた最大の食い込み(&バッチ, &予測),
        };
        let 終わりの項目: Vec<_> = バッチ
            .剛体と静的世界の接触拘束()
            .iter()
            .map(剛体と静的世界の接触拘束::細分の終わりの履歴の項目)
            .collect();
        self.履歴.細分の終わりの記録で置き換える(&終わりの項目).unwrap();
    }

    // 反復を終えた配置で最も深い食い込み。隔たりが正の点しか無ければ零である。
    pub(super) fn 反復を終えた最大の食い込み(
        &self, バッチ: &接触拘束の二つのバッチ, 予測: &予測の状態
    ) -> メートル {
        let 参加者 = 姿勢自由度の参加者::動的(*予測.配置(), &self.箱の質量特性);
        let 最も深い = バッチ
            .剛体と静的世界の接触拘束()
            .iter()
            .map(|拘束| -拘束.同時解法の一行にする(&参加者).隔たり().値())
            .fold(0.0, f32::max);
        メートル::生成する(最も深い)
    }
}
