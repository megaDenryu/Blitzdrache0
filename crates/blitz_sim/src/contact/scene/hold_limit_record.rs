//! 保持できる傾きの上限を測る計器(判断13の受入条件(a)の材料)。担当するのは、傾きの正接と鉛直軸まわりの回しを振って
//! 600刻みの坂に沿った変位を綴ることである。`slope_tests`が合否を判定し、この計器は表を作るだけである。
//! 判定する検査と分けているのは、こちらが受入条件の表を作り直すための走査であり、あちらが固定した1つの条件だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use std::f32::consts::PI;

use super::super::friction_coefficient::摩擦係数;
use super::slope_fixture::{一刻みの細分数, 坂の場面を組む};
use super::slope_geometry::坂の場面の条件;
use super::static_friction_method::場面の静止摩擦の解き方;

const 振る傾きの正接: [f32; 7] = [0.20, 0.44, 0.48, 0.50, 0.52, 0.55, 0.61];
const 見る刻み数: usize = 600;

fn 測る条件(傾きの正接: f32, 鉛直軸まわりの回し: f32) -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接,
        鉛直軸まわりの回し,
        静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    }
}

fn 坂に沿った変位を測る(条件: &坂の場面の条件) -> f32 {
    let mut 場面 = 坂の場面を組む(条件);
    let 初めの重心 = 場面.箱の配置.重心の位置();
    場面.細分を進める(見る刻み数 * 一刻みの細分数);
    場面.坂に沿った変位(初めの重心, 条件)
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 保持できる傾きの上限を記録する() {
    println!("傾きの正接 | 0度 | 30度 | 45度");
    for 正接 in 振る傾きの正接 {
        let 変位: Vec<String> = [0.0, PI / 6.0, PI / 4.0]
            .iter()
            .map(|回し| format!("{:.3e}", 坂に沿った変位を測る(&測る条件(正接, *回し))))
            .collect();
        println!("{正接} | {}", 変位.join(" | "));
    }
}
