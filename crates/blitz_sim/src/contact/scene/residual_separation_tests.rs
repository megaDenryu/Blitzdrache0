//! 解けずに残した接線変位を速度の再構成から除く契約の反証(判断24の反証(a)と(e))。担当するのは2つである。
//! 除く経路で、初めの食い込みの過渡を過ぎた細分7以降の、位置から再構成した下り向きの速さの絶対値が 1.0e-4 メートル毎秒を
//! 超えないこと(2026-09-08のIssue #59の裁定1)。除いた量が位置に溜まらないこと。
//! 上限 1.0e-4 の由来: 旧実装(重心の位置が単精度1本)では、坂に沿った位置が表現の刻み 8.53e-7 メートルの整数倍の間を毎細分とび、
//! 再構成した速さが ±4.09e-4 と 8.19e-4 メートル毎秒の間を減衰せずに往復した(`_doc/計測/剛体の接触の静止摩擦の数値契約の診断_2026-09-06.md`)。
//! 1.0e-4 はその最小の跳び 4.09e-4 の4分の1未満であり、旧実装では通らない。二段の位置の導入後の実測の最大は 2.3e-5 である
//! (`_doc/計測/剛体の接触の静止摩擦の2段の位置_2026-09-08.md` の表2・表3)。
//! 旧の反証(細分1から63の速さの符号の反転が4回以下・円錐の比の振れ幅が0.017以下)は、周期が消えた後の ±1e-5 の桁の雑音の符号を
//! 数えていて周期の有無を測れないため、裁定1でこの量へ置き換えた。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

#![allow(clippy::unwrap_used)]

use super::super::friction_coefficient::摩擦係数;
use super::residual_separation::場面の残差の分離;
use super::slope_fixture::{一刻みの細分数, 坂の場面を組む};
use super::slope_geometry::坂の場面の条件;
use super::static_friction_method::場面の静止摩擦の解き方;
use super::substep_harness::一つの箱と静的な直方体の場面;

const 見る細分の本数: usize = 64;
const 過渡を除いて測り始める細分の番号: usize = 7; // 細分0から6は初めの食い込みを解く過渡であり、法線の乗数が平衡の3.7倍ある
const 再構成した速さの絶対値の上限: f32 = 1.0e-4;
// 反証(e)の刻み数と、位置と速度の食い違いの上限。上限は解けたと見なす許容差 δ(この場面で約1.907e-6メートル)の4倍である。
// この差へ入りうるのは、その細分に持ち越しを破棄した点の残差(高々 δ)と、測り直した残差と仮の補正が線形化で
// 食い違う分(残差と同じ桁)の2つだけであり、どちらもどの細分でも同時に最大で δ の2倍に収まる。
// 倍率4はその見積りへ、細分1本の中で有効集合が入れ替わる場合の余地を同じだけ足した値である。
const 位置と速度の食い違いを見る刻み数: usize = 3600;
const 位置と速度の食い違いの上限: f32 = 7.6e-6;

fn 保持する坂の条件() -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接: 0.50,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    }
}

fn 場面を分離の扱いで組む(分離: 場面の残差の分離) -> 一つの箱と静的な直方体の場面 {
    let mut 場面 = 坂の場面を組む(&保持する坂の条件());
    場面.残差の分離 = 分離;
    場面
}

// 細分7から63までの、位置から再構成した坂の下り向きの速さの絶対値の最大。
fn 過渡の後の速さの絶対値の最大(分離: 場面の残差の分離) -> f32 {
    let 条件 = 保持する坂の条件();
    let mut 場面 = 場面を分離の扱いで組む(分離);
    let mut 最大: f32 = 0.0;
    for 番号 in 0..見る細分の本数 {
        場面.一細分進める();
        if 番号 >= 過渡を除いて測り始める細分の番号 {
            最大 = 最大.max(場面.下り向きの速さ(&条件).abs());
        }
    }
    最大
}

#[test]
fn 残差の変化を速度から除くと過渡の後の再構成した速さが一万分の一メートル毎秒を超えず除かないと超える() {
    let 除いた最大 = 過渡の後の速さの絶対値の最大(場面の残差の分離::残差の変化を速度から除く);
    assert!(
        除いた最大 <= 再構成した速さの絶対値の上限,
        "細分7以降の再構成した速さの絶対値が上限を超えた: {除いた最大:e}"
    );
    let 運ばせた最大 = 過渡の後の速さの絶対値の最大(場面の残差の分離::残差の変化を速度へ運ばせる);
    assert!(
        運ばせた最大 > 再構成した速さの絶対値の上限,
        "残差を速度へ運ばせる反証が上限を超えていない: {運ばせた最大:e}"
    );
}

#[test]
fn 速度から除いた量が位置に溜まらない() {
    let 条件 = 保持する坂の条件();
    let mut 場面 = 場面を分離の扱いで組む(場面の残差の分離::残差の変化を速度から除く);
    let 初めの重心 = 場面.箱の配置.重心の位置();
    let 刻み幅の秒 = 場面.刻み幅.秒().値();
    let (mut 速度の累積, mut 最大の食い違い) = (0.0, 0.0f32);
    for _ in 0..(位置と速度の食い違いを見る刻み数 * 一刻みの細分数) {
        場面.一細分進める();
        速度の累積 += 場面.下り向きの速さ(&条件) * 刻み幅の秒;
        最大の食い違い = 最大の食い違い.max((速度の累積 - 場面.坂に沿った変位(初めの重心, &条件)).abs());
    }
    assert!(
        最大の食い違い <= 位置と速度の食い違いの上限,
        "速度の累積と配置の変位の差が上限を超えた: {最大の食い違い}"
    );
}
