//! 解けずに残した接線変位を速度の再構成から除く契約の反証(判断24の反証(a)と(e))。担当するのは2つである。
//! 除く経路では細分の単位の周期が消え、除かない経路では残ること。除いた量が位置に溜まらないこと。
//! 閾値の由来は第1段階の実測(`_doc/計測/剛体の接触の静止摩擦の数値契約の診断_2026-09-06.md` の表6)であり、
//! 正接0.50・回し0度・許容差1倍で符号の反転が46回、円錐の比の振れ幅が0.1687であった。閾値はその10分の1より
//! 小さい値に置く。周期が残っていれば実測に近い値が出るため、10分の1を偶然満たすことはない。
//! 零にしないのは、残差の測り直しと有効集合の入れ替わりが1本ずつの細分に有界の揺れを残すことを許すためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

#![allow(clippy::unwrap_used)]

use super::super::friction_coefficient::摩擦係数;
use super::residual_separation::場面の残差の分離;
use super::slope_fixture::{一刻みの細分数, 坂の場面を組む};
use super::slope_geometry::坂の場面の条件;
use super::static_friction_method::場面の静止摩擦の解き方;
use super::substep_harness::一つの箱と静的な直方体の場面;

const 見る細分の本数: usize = 64;
const 符号の反転の上限: usize = 4; // 第1段階の実測46回の10分の1より小さい
const 比の振れ幅の上限: f64 = 0.017; // 第1段階の実測0.1687の10分の1より小さい
// 反証(e)の刻み数と、位置と速度の食い違いの上限。上限は解けたと見なす許容差 δ(この場面で約1.907e-6メートル)の4倍である。
// この差へ入りうるのは、その細分に持ち越しを破棄した点の残差(高々 δ)と、測り直した残差と仮の補正が線形化で
// 食い違う分(残差と同じ桁)の2つだけであり、どちらもどの細分でも同時に最大で δ の2倍に収まる。
// 倍率4はその見積りへ、細分1本の中で有効集合が入れ替わる場合の余地を同じだけ足した値である。
const 位置と速度の食い違いを見る刻み数: usize = 3600;
const 位置と速度の食い違いの上限: f32 = 7.6e-6;

fn 保持する坂の条件() -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接: 0.50,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    }
}

fn 場面を分離の扱いで組む(分離: 場面の残差の分離) -> 一つの箱と静的な直方体の場面 {
    let mut 場面 = 坂の場面を組む(&保持する坂の条件());
    場面.残差の分離 = 分離;
    場面
}

// 細分1から見る本数までの、円錐の比の振れ幅と下り向きの速さの符号の反転の回数。細分0は初めの食い込みを解く
// 過渡であり、法線の乗数が平衡の3.7倍あって比が桁で小さく出るため除く。
fn 周期の大きさを測る(分離: 場面の残差の分離) -> (f64, usize) {
    let 条件 = 保持する坂の条件();
    let mut 場面 = 場面を分離の扱いで組む(分離);
    let (mut 比の並び, mut 速さの並び) = (Vec::new(), Vec::new());
    for 番号 in 0..見る細分の本数 {
        場面.一細分進める();
        let 観測 = 場面.直前の細分の観測;
        if 番号 > 0 && 観測.法線の乗数の合計.値() > 0.0 {
            比の並び.push(f64::from(観測.接線の乗数の合力の大きさ.値()) / f64::from(観測.法線の乗数の合計.値()));
        }
        速さの並び.push(場面.下り向きの速さ(&条件));
    }
    let 振れ幅 = 比の並び.iter().copied().fold(f64::MIN, f64::max) - 比の並び.iter().copied().fold(f64::MAX, f64::min);
    let 反転 = 速さの並び
        .get(1..)
        .unwrap_or_default()
        .windows(2)
        .filter(|組| 組[0] * 組[1] < 0.0)
        .count();
    (振れ幅, 反転)
}

#[test]
fn 残差の変化を速度から除くと細分の周期が消え除かないと残る() {
    let (除いた振れ幅, 除いた反転) = 周期の大きさを測る(場面の残差の分離::残差の変化を速度から除く);
    assert!(除いた反転 <= 符号の反転の上限, "速さの符号の反転が多すぎる: {除いた反転}回");
    assert!(除いた振れ幅 <= 比の振れ幅の上限, "円錐の比の振れ幅が大きすぎる: {除いた振れ幅}");
    let (運ばせた振れ幅, 運ばせた反転) = 周期の大きさを測る(場面の残差の分離::残差の変化を速度へ運ばせる);
    assert!(
        運ばせた反転 > 符号の反転の上限 || 運ばせた振れ幅 > 比の振れ幅の上限,
        "残差を速度へ運ばせる反証が閾値を超えていない: 反転{運ばせた反転}回 振れ幅{運ばせた振れ幅}"
    );
}

#[test]
fn 速度から除いた量が位置に溜まらない() {
    let 条件 = 保持する坂の条件();
    let mut 場面 = 場面を分離の扱いで組む(場面の残差の分離::残差の変化を速度から除く);
    let 初めの重心 = 場面.箱の配置.重心の位置();
    let 刻み幅の秒 = 場面.刻み幅.秒().値();
    let (mut 速度の累積, mut 最大の食い違い) = (0.0, 0.0f32);
    for _ in 0..(位置と速度の食い違いを見る刻み数 * 一刻みの細分数) {
        場面.一細分進める();
        速度の累積 += 場面.下り向きの速さ(&条件) * 刻み幅の秒;
        最大の食い違い = 最大の食い違い.max((速度の累積 - 場面.坂に沿った変位(初めの重心, &条件)).abs());
    }
    assert!(
        最大の食い違い <= 位置と速度の食い違いの上限,
        "速度の累積と配置の変位の差が上限を超えた: {最大の食い違い}"
    );
}
