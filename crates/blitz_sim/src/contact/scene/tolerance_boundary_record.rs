//! 許容差の境界の走査の表を綴る計器(判断13の2026-09-12の実装の細目の反証(4)(b)の材料)。担当するのは、傾きの正接
//! 0.45から0.55までを、原点の場面と法線の向きへ20.4999メートル動かして許容差を2倍にした場面の2つ、受理の許容差の
//! 倍率0.5倍・1倍・2倍の3つで走らせ、保持と滑走の分類と坂に沿った変位を綴ることである。合否は判定しない。
//! 正接0.50未満をこの計器へ置くのは、`tolerance_boundary_tests` が固定する範囲を27組の下限である0.50以上に限り、
//! それ未満の行は退避の機構(Issue #99)の影響を受けて分類が動きうるためである(記録の表27・表32)。
//! 実行は `cargo test -p blitz_sim --release 許容差の境界の走査を綴る -- --ignored --nocapture` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::slope_holding::坂の箱の保持と滑走;
use super::tolerance_boundary_scan::許容差の境界の走査;

const 走査する傾きの正接: &[f32] = &[0.45, 0.46, 0.47, 0.48, 0.49, 0.50, 0.51, 0.52, 0.53, 0.54, 0.55];
// 坂の中心から接触点までの長さ。これだけ法線の向きへ動かすと接触点の座標が2倍になり、表現の刻みが2倍になる。
const 許容差を二倍にする長さ: f32 = 20.4999;
const 振る受理の倍率: &[f32] = &[0.5, 1.0, 2.0];

fn 分類の綴り(分類: 坂の箱の保持と滑走) -> &'static str {
    match 分類 {
        坂の箱の保持と滑走::保持 => "保持",
        坂の箱の保持と滑走::滑走 => "滑走",
    }
}

fn 一本の走査を綴る(見出し: &str, 動かす長さ: f32, 受理の倍率: f32) {
    let 走査 = 許容差の境界の走査::動かす長さと受理の倍率から生成する(動かす長さ, 受理の倍率);
    let 行: Vec<String> = 走査する傾きの正接
        .iter()
        .map(|&正接| {
            let (分類, 変位) = 走査.分類と坂に沿った変位(正接);
            format!("{正接}={}({変位:.3e})", 分類の綴り(分類))
        })
        .collect();
    println!("[{見出し}] {}", 行.join(" "));
    println!(
        "  下端から連続して保持する最後の正接={:?}",
        走査.下端から連続して保持する最後の正接(走査する傾きの正接)
    );
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 許容差の境界の走査を綴る() {
    for &受理の倍率 in 振る受理の倍率 {
        一本の走査を綴る(&format!("原点_受理{受理の倍率}倍"), 0.0, 受理の倍率);
        一本の走査を綴る(&format!("移動20.4999_受理{受理の倍率}倍"), 許容差を二倍にする長さ, 受理の倍率);
    }
}
