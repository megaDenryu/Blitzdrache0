//! 細分1本の残差まわりの観測(判断24の診断)。担当するのは、粘着の候補を確定した点の数・残差の変化を持った点の数・
//! 変化の最大の長さ・細分の終わりの残差の最大の長さ・仮の補正を引く前の並進速度の5つを運ぶことである。
//! 細分の観測(`scene_settings`)から分けているのは、あちらが接触点と乗数と食い込みという解法の結果を運ぶのに対し、
//! こちらが判断24の契約が何をしたかだけを運ぶからである。5つを平らに並べると、観測の欄が12になって由来が混ざる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

#![cfg(test)]

use blitz_math::{メートル, ワールド, 速度};

/// 細分1本で判断24の契約が何をしたかの観測。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 細分の残差の観測 {
    pub 粘着の候補を確定した点の数: usize,
    pub 残差の変化が在る点の数: usize,
    pub 残差の変化の最大の長さ: メートル,
    pub 細分の終わりの残差の最大の長さ: メートル,
    pub 仮の補正を引く前の並進速度: 速度<ワールド>,
}

impl Default for 細分の残差の観測 {
    fn default() -> Self {
        Self {
            粘着の候補を確定した点の数: 0,
            残差の変化が在る点の数: 0,
            残差の変化の最大の長さ: メートル::生成する(0.0),
            細分の終わりの残差の最大の長さ: メートル::生成する(0.0),
            仮の補正を引く前の並進速度: 速度::零(),
        }
    }
}
