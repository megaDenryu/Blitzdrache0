//! 場面の1細分ぶんの接触拘束のバッチを組む工程(判断11・19の試験専用の実装)。細分の力学(`substep_step`)から
//! 分けているのは、こちらが受け取るのが予測した配置1つだけであり、返すのがバッチ1つだけの独立した工程だからである。
//! この工程が触れるのは、場面が持つ形と材質と刻み幅であって、細分の反復が書き換える予測でも履歴でもない。
//! 参照軸の選択が読む優位幅と、切り抜きが読む接触生成の余白を、本番と同じ導出で対にして問い合わせへ渡す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_collision::contact_set::{
    二つの直方体の重なりの接触点集合, 接触点集合, 直方体どうしの接触の特徴の対, 直方体どうしの接触点集合の問い合わせ,
};

use super::super::batch_builder::接触拘束のバッチの組み立て;
use super::super::contact_batches::接触拘束の二つのバッチ;
use super::super::contacting_body::接触に参加する剛体;
use super::super::generation_margin::{
    接触生成の余白を導く形の運動, 細分の運動から接触生成の余白を導く, 細分の静穏の運動から外積の軸へ切り替える優位幅を導く,
};
use super::super::material_id::材質の識別子;
use super::super::minimum_thickness::形の最小の厚み;
use super::scene_geometry::{場面の材質, 直方体を組む};
use super::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_xpbd::予測の状態;
use crate::xpbd::コンプライアンス;

impl 一つの箱と静的な直方体の場面 {
    pub(super) fn 接触拘束のバッチを組む(&self, 予測: &予測の状態) -> 接触拘束の二つのバッチ {
        let 剛体 = 接触に参加する剛体::生成する(
            self.箱の識別子,
            *予測.配置(),
            材質の識別子::生成する(場面の材質),
            形の最小の厚み::生成する(self.箱の半分の長さ * 2.0).unwrap(),
        );
        let mut 組み立て = 接触拘束のバッチの組み立て::生成する(&self.混合則, コンプライアンス::硬い(), self.刻み幅, 1);
        if let Some(集合) = self.接触点集合を求める(予測) {
            組み立て.剛体と静的世界の接触点集合を積む(&剛体, &self.静的世界の接触相手, &集合).unwrap();
        }
        let mut バッチ = 組み立て.二つのバッチを組み立てる();
        バッチ.鍵の昇順へ並べ替える();
        バッチ
    }

    fn 接触点集合を求める(&self, 予測: &予測の状態) -> Option<接触点集合<直方体どうしの接触の特徴の対>> {
        let 箱 = 直方体を組む(予測.配置(), self.箱の半分の長さ);
        let 静的な箱 = &self.静的な直方体;
        let 箱の運動 = 接触生成の余白を導く形の運動::動く形から生成する(&箱, self.箱の運動状態);
        let 静的な形の運動 = 接触生成の余白を導く形の運動::静止した形から生成する(静的な箱);
        let 余白 = 細分の運動から接触生成の余白を導く(&箱の運動, &静的な形の運動, self.刻み幅).unwrap();
        let 優位幅 = 細分の静穏の運動から外積の軸へ切り替える優位幅を導く(&箱の運動, &静的な形の運動, self.刻み幅).unwrap();
        let 問い = 直方体どうしの接触点集合の問い合わせ::二つの直方体と余白と優位幅から生成する(
            &箱,
            静的な箱,
            余白,
            優位幅,
        );
        match 問い.二つの直方体の重なりの接触点集合を求める().unwrap() {
            二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) => Some(集合),
            二つの直方体の重なりの接触点集合::二つの直方体は離れている => None,
        }
    }
}
