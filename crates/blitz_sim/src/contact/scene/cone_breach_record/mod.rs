//! 保持と滑走の境界の周囲で、接触点集合がクーロン円錐を超える細分を探して内訳を綴る計器(判断13の原因の分離)。
//! 担当するのは3つの走査である。傾きの正接を百分の一刻みで振って円錐を初めて超える細分の番号を並べる走査、
//! 境界の周囲の5つの組について超えた細分と共通の細分の内訳を綴る走査、保持しているあいだの円錐の比の推移を
//! 細分の番号を飛ばしながら綴る走査である。細分1本の内訳は、位置の反復の3つの地点(非貫通の前・非貫通の後・
//! 接線解の後)の量である。
//! 合否は判定しない。判定する検査は`slope_tests`が持つ。実行は
//! `cargo test -p blitz_sim --release 円錐を超える細分 -- --ignored --nocapture` である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

mod eigen_direction_readers;
mod instrumented_substep;
mod manifold_observation;
mod point_observation;
mod record_line;
mod recorded_case;
mod tangential_system_observation;

use recorded_case::記録する一つの場合;

pub(super) const 静止摩擦係数の値: f32 = 0.6;
// 600刻み(4800細分)の受入条件が見る範囲の10倍まで探す。保持に見える場合が単に遅れているだけかを分けるためである。
const 円錐を超える細分を探す上限: usize = 48000;
// 場合どうしを同じ地点で比べる細分の番号。45度の正接0.52がこの細分で円錐を超える。
const 比べる細分の番号: usize = 1;
// 円錐の比の推移を綴る細分の番号。回し0度・正接0.50が30736本目で超えるまでの間を飛ばしながら見る。
const 比の推移を綴る細分の番号: [usize; 8] = [1, 100, 1000, 5000, 10000, 20000, 30000, 30735];

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 境界の周囲で円錐を超える細分を走査する() {
    for 場合 in 記録する一つの場合::境界の周囲を走査する並び() {
        match 場合.円錐を初めて超えた細分の番号(円錐を超える細分を探す上限) {
            Some(番号) => println!("[{}] {番号}本目で超えた", 場合.見出し),
            None => println!("[{}] {円錐を超える細分を探す上限}細分のあいだ超えず", 場合.見出し),
        }
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 円錐を超える細分の内訳を記録する() {
    for 場合 in 記録する一つの場合::内訳を記録する並び() {
        let 超えた番号 = 場合.円錐を初めて超えた細分の番号(円錐を超える細分を探す上限);
        match 超えた番号 {
            Some(番号) => println!("[{}] 円錐を初めて超えた細分は{番号}本目である", 場合.見出し),
            None => println!("[{}] {円錐を超える細分を探す上限}細分のあいだ円錐を超えなかった", 場合.見出し),
        }
        for 番号 in [Some(比べる細分の番号), 超えた番号].into_iter().flatten() {
            場合.細分の内訳を綴る(番号);
        }
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 保持しているあいだの円錐の比の推移を記録する() {
    let 場合 = 記録する一つの場合::回しと正接から生成する(0.0, 0.50);
    for 番号 in 比の推移を綴る細分の番号 {
        場合.細分の内訳を綴る(番号);
    }
}
