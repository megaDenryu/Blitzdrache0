//! 記録の1地点で接触点集合1つから読む集計(判断13の原因の分離のための計器)。担当するのは、点ごとの観測を集めて
//! Σλ_n・Σλ_t・Σ‖λ_t,i‖・接触点集合の中心まわりのモーメントの大きさ ‖Σ(r_i × λ_t,i)‖ を求めることである。
//! 点ごとの観測(`point_observation`)から分けているのは、こちらが集合の単位の量だけを持ち、あちらが1点の読み取りだからである。
//! ねじりの成分が乗るのはモーメントであり、この計器はそれが並進の合力に対してどの桁かを見るために置いた。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_math::{キログラム平方メートル, ワールド, 位置, 変位};

use super::point_observation::接触点の観測;
use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::static_friction::接線のラグランジュ乗数;
use crate::rigid_xpbd::姿勢自由度の参加者;
use crate::xpbd::ラグランジュ乗数;

/// 記録の1地点で接触点集合1つから読んだ集計。
pub(super) struct 接触点集合の観測 {
    pub(super) 点ごと: Vec<接触点の観測>,
}

impl 接触点集合の観測 {
    pub(super) fn 接触点集合から読む(
        接触点集合: &[剛体と静的世界の接触拘束], 剛体: &姿勢自由度の参加者
    ) -> Self {
        Self {
            点ごと: 接触点集合.iter().map(|拘束| 接触点の観測::拘束から読む(拘束, 剛体)).collect(),
        }
    }

    /// 法線の乗数の合計 Σλ_n。
    pub(super) fn 法線の乗数の合計(&self) -> ラグランジュ乗数 {
        self.点ごと.iter().fold(ラグランジュ乗数::零(), |合計, 点| 合計 + 点.法線の乗数)
    }

    /// 接線の乗数の合力 Σλ_t。円錐の判定が読む量である。
    pub(super) fn 接線の乗数の合力(&self) -> 接線のラグランジュ乗数 {
        self.点ごと.iter().fold(接線のラグランジュ乗数::零(), |合計, 点| 合計 + 点.接線の乗数)
    }

    /// 点ごとの大きさの和 Σ‖λ_t,i‖。合力の大きさで割ると、点どうしが打ち消し合う内部の成分の強さになる。
    pub(super) fn 接線の乗数の大きさの和(&self) -> ラグランジュ乗数 {
        self.点ごと.iter().fold(ラグランジュ乗数::零(), |合計, 点| 合計 + 点.接線の乗数.大きさ())
    }

    /// 接触点集合の中心まわりの接線の乗数のモーメントの大きさ ‖Σ(r_i × λ_t,i)‖。ねじりの成分が乗る量である。
    pub(super) fn 接線の乗数のモーメントの大きさ(&self) -> キログラム平方メートル {
        let 中心 = self.接触点集合の中心();
        let (mut x, mut y, mut z) = (0.0, 0.0, 0.0);
        for 点 in &self.点ごと {
            let 腕 = 点.接触点の世界位置 - 中心;
            let (乗数x, 乗数y, 乗数z) = 点.接線の乗数.三つの成分();
            x += 腕.y().値() * 乗数z.値() - 腕.z().値() * 乗数y.値();
            y += 腕.z().値() * 乗数x.値() - 腕.x().値() * 乗数z.値();
            z += 腕.x().値() * 乗数y.値() - 腕.y().値() * 乗数x.値();
        }
        キログラム平方メートル::生成する((x * x + y * y + z * z).sqrt())
    }

    fn 接触点集合の中心(&self) -> 位置<ワールド> {
        let mut 個数 = 0.0;
        let mut 合計 = 変位::零();
        for 点 in &self.点ごと {
            個数 += 1.0;
            合計 = 合計 + 点.接触点の世界位置.原点からの変位();
        }
        let 平均 = 合計.比で伸ばす(1.0 / 個数);
        位置::生成する(平均.x(), 平均.y(), 平均.z())
    }
}
