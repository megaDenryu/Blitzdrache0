//! 記録の1地点で組んだ法線と接線の連立と、それを解いた結果(判断13の原因の分離のための計器)。担当するのは、
//! いまの接触点と錨と予測の配置から連立を組んで解き、対称行列 J M⁻¹ Jᵀ と右辺と行ごとの許容差と解を保つことと、
//! 円錐の判定が読む2つの量(更新後の Σλ_n と、更新後の接線の合力の大きさ)と点ごとの有効集合を保つことである。
//! 固有分解の内訳を読む口は`eigen_direction_readers`が持つ。分けているのは、あちらが分解と右辺と許容差の3つだけに
//! 触れる読み取りであり、こちらが連立を組んで解く工程だからである。
//! 連立の抜き出しは有効集合に絞るが、この計器は全部の行で組む。捨てられた向きがどこに乗っているかを見るためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::contact_projection_row::一行の二つの符号付き勾配;
use crate::contact::normal_tangential_system::接触点集合の法線と接線の連立;
use crate::contact::static_friction::接線のラグランジュ乗数;
use crate::contact::symmetric_system::{対称な連立の固有分解, 法線と接線の連立の行の上限};
use crate::rigid_xpbd::姿勢自由度の参加者;
use crate::xpbd::ラグランジュ乗数;

/// 記録の1地点の法線と接線の連立と、それを解いた結果。
pub(super) struct 接線の連立の観測 {
    有効逆質量行列: [[f32; 法線と接線の連立の行の上限]; 法線と接線の連立の行の上限],
    解: [f32; 法線と接線の連立の行の上限],
    pub(super) 右辺: [f32; 法線と接線の連立の行の上限],
    pub(super) 行ごとの解けたと見なす許容差: [f32; 法線と接線の連立の行の上限],
    pub(super) 分解: 対称な連立の固有分解,
    pub(super) 行の数: usize,
    更新後の法線の乗数の合計: ラグランジュ乗数,
    更新後の接線の合力の大きさ: f32,
    点ごとの法線の行が有効か: Vec<bool>,
}

impl 接線の連立の観測 {
    /// いまの接触点と錨と予測の配置から連立を組み直して解く。連立へ入らなかった点は行を持たない。
    pub(super) fn 接触点集合から組む(
        接触点集合: &[剛体と静的世界の接触拘束], 剛体: &姿勢自由度の参加者
    ) -> Self {
        let mut 連立 = 接触点集合の法線と接線の連立::点の数から空で始める(接触点集合.len());
        for (添字, 拘束) in 接触点集合.iter().enumerate() {
            拘束.法線と接線の連立へ法線の一行を積む(添字, &mut 連立, 剛体);
            拘束.法線と接線の連立へ接線の一行を積む(添字, &mut 連立, 剛体);
        }
        let 同時解 = 連立.相補条件を満たす有効集合で同時に解く().定まった解を取り出す();
        let mut 勾配の並び = Vec::new();
        let mut 右辺 = [0.0; 法線と接線の連立の行の上限];
        let mut 行ごとの解けたと見なす許容差 = [0.0; 法線と接線の連立の行の上限];
        let mut 解 = [0.0; 法線と接線の連立の行の上限];
        let mut 仮の合力 = 接線のラグランジュ乗数::零();
        let mut 更新後の法線の乗数の合計 = ラグランジュ乗数::零();
        let mut 点ごとの法線の行が有効か = Vec::new();
        for 番号 in 0..連立.点の数() {
            点ごとの法線の行が有効か.push(同時解.一点の法線の行が有効か(番号));
            if let Some(法線の行) = 連立.法線の一行を読む(番号) {
                解[勾配の並び.len()] = 同時解.一点の法線の乗数の増分(番号).値();
                右辺[勾配の並び.len()] = 法線の行.連立の右辺().値();
                行ごとの解けたと見なす許容差[勾配の並び.len()] = 法線の行.勾配().解けたと見なす許容差().値();
                勾配の並び.push(*法線の行.勾配());
                更新後の法線の乗数の合計 =
                    更新後の法線の乗数の合計 + 法線の行.法線のラグランジュ乗数() + 同時解.一点の法線の乗数の増分(番号);
            }
            if let Some(接線の行) = 連立.接線の一行を読む(番号) {
                let 増分 = 同時解.一点の接線の乗数の増分(番号);
                解[勾配の並び.len()] = 増分.値();
                右辺[勾配の並び.len()] = 接線の行.連立の右辺().値();
                行ごとの解けたと見なす許容差[勾配の並び.len()] = 接線の行.勾配().解けたと見なす許容差().値();
                勾配の並び.push(*接線の行.勾配());
                仮の合力 = 仮の合力 + 接線のラグランジュ乗数::零().向きへの増分を足す(接線の行.接線の向き(), 増分);
            }
        }
        Self {
            有効逆質量行列: 行列を組む(&勾配の並び),
            分解: 対称な連立の固有分解::分解する(&行列を組む(&勾配の並び), 勾配の並び.len()),
            行の数: 勾配の並び.len(),
            更新後の接線の合力の大きさ: 仮の合力.大きさ().値(),
            更新後の法線の乗数の合計,
            点ごとの法線の行が有効か,
            右辺,
            行ごとの解けたと見なす許容差,
            解,
        }
    }

    /// この地点で解いた増分を足したときの接線の乗数の合力 ‖Σ(λ_t,i + Δs_i t_i)‖。円錐の判定が読む値である。
    pub(super) fn 更新後の接線の合力の大きさ(&self) -> f32 {
        self.更新後の接線の合力の大きさ
    }

    /// この地点で解いた増分を足したときの法線の乗数の合計 Σ(λ_n,i + Δλ_n,i)。円錐の半径を決める値である。
    pub(super) fn 更新後の法線の乗数の合計(&self) -> f32 {
        self.更新後の法線の乗数の合計.値()
    }

    /// 有効集合の組み替えが止まった時点で、点ごとに法線の行が有効集合へ残ったか。
    pub(super) fn 点ごとの法線の行が有効か(&self) -> &[bool] {
        &self.点ごとの法線の行が有効か
    }

    /// 捨てた後の残差 ‖J M⁻¹ Jᵀ Δλ − b‖。
    pub(super) fn 捨てた後の残差(&self) -> f32 {
        let mut 二乗和 = 0.0;
        for k in 0..self.行の数 {
            let 積: f32 = (0..self.行の数).map(|l| self.有効逆質量行列[k][l] * self.解[l]).sum();
            二乗和 += (積 - self.右辺[k]) * (積 - self.右辺[k]);
        }
        二乗和.sqrt()
    }
}

// 行の勾配の並びから対称行列を組む。行どうしの交差に対して対等な計算であるためレシーバを持たない。
fn 行列を組む(
    勾配の並び: &[一行の二つの符号付き勾配],
) -> [[f32; 法線と接線の連立の行の上限]; 法線と接線の連立の行の上限] {
    let mut 行列 = [[0.0; 法線と接線の連立の行の上限]; 法線と接線の連立の行の上限];
    for (k, 自分) in 勾配の並び.iter().enumerate() {
        for (l, 相手) in 勾配の並び.iter().enumerate() {
            行列[k][l] = 自分.交差の寄与(相手).値();
        }
    }
    行列
}
