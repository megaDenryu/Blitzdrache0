//! 記録の1地点で組んだ接線の連立と、その固有分解の内訳(判断13の原因の分離のための計器)。担当するのは、
//! いまの錨と予測の配置から W_t と −C_t を組み、固有値・固有値の最大に対する比・各固有ベクトルへの右辺の射影・
//! 小さい向きを捨てた解の残差 ‖W_t Δs + C_t‖ を求めることである。
//! 連立の型が持つ行列の組み立ては私有であるため、ここでは行の公開の口(交差の有効逆質量と右辺)から同じ行列を組み直す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_collision::contact_set::接触点の上限;

use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::static_friction::接線のラグランジュ乗数;
use crate::contact::static_friction::接触点集合の静止摩擦の連立;
use crate::contact::static_friction::静止摩擦の接触点集合の一行;
use crate::contact::symmetric_system::対称な連立の固有分解;
use crate::rigid_xpbd::姿勢自由度の参加者;
use crate::xpbd::ラグランジュ乗数;

/// 記録の1地点の接線の連立とその固有分解。
pub(super) struct 接線の連立の観測 {
    行の並び: Vec<静止摩擦の接触点集合の一行>,
    有効逆質量行列: [[f32; 接触点の上限]; 接触点の上限],
    右辺: [f32; 接触点の上限],
    解: [f32; 接触点の上限],
    分解: 対称な連立の固有分解,
    行の数: usize,
}

impl 接線の連立の観測 {
    /// いまの錨と予測の配置から連立を組み直して分解する。連立へ入らなかった点は行を持たない。
    pub(super) fn 接触点集合から組む(
        接触点集合: &[剛体と静的世界の接触拘束], 剛体: &姿勢自由度の参加者
    ) -> Self {
        let mut 連立 = 接触点集合の静止摩擦の連立::点の数から空で始める(接触点集合.len());
        for (添字, 拘束) in 接触点集合.iter().enumerate() {
            拘束.静止摩擦の連立へ一行を積む(添字, &mut 連立, 剛体);
        }
        let 行の並び: Vec<_> = (0..接触点集合.len()).filter_map(|番号| 連立.一行を読む(番号)).collect();
        let mut 有効逆質量行列 = [[0.0; 接触点の上限]; 接触点の上限];
        let mut 右辺 = [0.0; 接触点の上限];
        let mut 行ごとの丸めの大きさ = [0.0; 接触点の上限];
        for (k, 自分) in 行の並び.iter().enumerate() {
            右辺[k] = 自分.連立の右辺().値();
            行ごとの丸めの大きさ[k] = 自分.右辺の丸めの大きさ().値();
            for (l, 相手) in 行の並び.iter().enumerate() {
                有効逆質量行列[k][l] = 自分.有効逆質量の交差の寄与(相手).値();
            }
        }
        let 分解 = 対称な連立の固有分解::分解する(&有効逆質量行列, 行の並び.len());
        let 解 = 分解.擬似逆で解く(&右辺, &行ごとの丸めの大きさ);
        Self {
            有効逆質量行列,
            右辺,
            解,
            分解,
            行の数: 行の並び.len(),
            行の並び,
        }
    }

    /// この地点で解いた増分を足したときの仮の接線の乗数の合力 ‖Σ(λ_t,i + Δs_i t_i)‖。円錐の判定が読む値である。
    pub(super) fn 仮の合力の大きさ(&self) -> f32 {
        let mut 合力 = 接線のラグランジュ乗数::零();
        for (k, 一行) in self.行の並び.iter().enumerate() {
            合力 =
                合力 + 一行.乗数の増分を足した接線の乗数(ラグランジュ乗数::有効逆質量で割った長さから生成する(self.解[k]));
        }
        合力.大きさ().値()
    }

    pub(super) fn 行の数(&self) -> usize {
        self.行の数
    }

    /// 第k番の固有値と、固有値の最大に対する比。
    pub(super) fn 固有値と比(&self, k: usize) -> (f32, f32) {
        let 最大 = (0..self.行の数).map(|番号| self.分解.第k番の固有値(番号)).fold(0.0, f32::max);
        let 固有値 = self.分解.第k番の固有値(k);
        (固有値, if 最大 > 0.0 { 固有値 / 最大 } else { 0.0 })
    }

    /// 第k番の固有ベクトルへの右辺の射影 v_kᵀ b。
    pub(super) fn 右辺の射影(&self, k: usize) -> f32 {
        (0..self.行の数).map(|i| self.分解.第k番の固有ベクトルの成分(k, i) * self.右辺[i]).sum()
    }

    /// 小さい向きを捨てた解の残差 ‖W_t Δs + C_t‖(右辺が −C_t であるため W_t Δs − 右辺 の大きさである)。
    pub(super) fn 捨てた後の残差(&self) -> f32 {
        let mut 二乗和 = 0.0;
        for k in 0..self.行の数 {
            let 積: f32 = (0..self.行の数).map(|l| self.有効逆質量行列[k][l] * self.解[l]).sum();
            二乗和 += (積 - self.右辺[k]) * (積 - self.右辺[k]);
        }
        二乗和.sqrt()
    }
}
