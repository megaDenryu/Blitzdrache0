//! 記録の1地点を1つの行の束として綴る工程(判断13の原因の分離のための計器)。担当するのは、点ごとの観測・集合の集計・
//! 接線の連立の内訳を、生の数値のまま標準出力へ書き出すことである。
//! 反復を回す側(`instrumented_substep`)から分けているのは、こちらが1地点ごとに呼ばれる綴りであり、あちらが細分1本の
//! 工程だからである。合否は判定しない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::manifold_observation::接触点集合の観測;
use super::tangential_system_observation::接線の連立の観測;
use super::静止摩擦係数の値;
use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::scene::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_xpbd::{予測の状態, 姿勢自由度の参加者};

impl 一つの箱と静的な直方体の場面 {
    // 1地点の記録を綴る。この場面は接触点集合を高々1つしか持たないため、バッチの全部の拘束が1つの集合である。
    pub(super) fn 記録の一地点を綴る(
        &self,
        見出し: &str,
        反復番号: u32,
        地点: &str,
        接触点集合: &[剛体と静的世界の接触拘束],
        予測: &予測の状態,
    ) {
        let 剛体 = 姿勢自由度の参加者::動的(*予測.配置(), &self.箱の質量特性);
        let 観測 = 接触点集合の観測::接触点集合から読む(接触点集合, &剛体);
        let 滑走中の数 = 接触点集合.iter().filter(|拘束| 拘束.静止摩擦の解の状態().滑走中か()).count();
        println!("[{見出し}] 反復{反復番号} {地点} 点数{} 滑走中の点{滑走中の数}", 観測.点ごと.len());
        for (番号, 点) in 観測.点ごと.iter().enumerate() {
            let 変位 = 点.錨からの接線変位;
            let (乗数x, 乗数y, 乗数z) = 点.接線の乗数.三つの成分();
            println!(
                "  点{番号} 特徴={:?} 有効={} C_n={:.6e} 接線変位=({:.6e},{:.6e},{:.6e}) |接線変位|={:.6e} λ_n={:.6e} λ_t=({:.6e},{:.6e},{:.6e}) |λ_t|={:.6e}",
                点.特徴の識別,
                点.法線の有効集合に入るか,
                点.隔たり.値(),
                変位.x().値(),
                変位.y().値(),
                変位.z().値(),
                変位.長さ().値(),
                点.法線の乗数.値(),
                乗数x.値(),
                乗数y.値(),
                乗数z.値(),
                点.接線の乗数.大きさ().値(),
            );
        }
        self.集合の集計を綴る(&観測);
        self.接線の連立を綴る(&接線の連立の観測::接触点集合から組む(接触点集合, &剛体), &観測);
    }

    fn 集合の集計を綴る(&self, 観測: &接触点集合の観測) {
        let 合力 = 観測.接線の乗数の合力().大きさ().値();
        let 法線 = 観測.法線の乗数の合計().値();
        println!(
            "  集計 Σλ_n={法線:.6e} ‖Σλ_t‖={合力:.6e} 比={:.6e} Σ‖λ_t‖÷‖Σλ_t‖={:.6e} |モーメント|={:.6e}",
            if 法線 > 0.0 { 合力 / 法線 } else { 0.0 },
            if 合力 > 0.0 {
                観測.接線の乗数の大きさの和().値() / 合力
            } else {
                0.0
            },
            観測.接線の乗数のモーメントの大きさ().値(),
        );
    }

    fn 接線の連立を綴る(&self, 連立: &接線の連立の観測, 観測: &接触点集合の観測) {
        let _ = 観測;
        print!("  接線の連立 行数={} 有効集合={:?}", 連立.行の数, 連立.点ごとの法線の行が有効か());
        for k in 0..連立.行の数 {
            let (固有値, 比) = 連立.固有値と比(k);
            print!(
                " [{k}] λ={固有値:.6e} 比={比:.6e} vᵀb={:.6e} δ={:.6e} {:?}",
                連立.右辺の射影(k),
                連立.許容差の射影(k),
                連立.第k番の向きを捨てた理由(k),
            );
        }
        println!(" 残差={:.6e}", 連立.捨てた後の残差());
        let 円錐の半径 = 静止摩擦係数の値 * 連立.更新後の法線の乗数の合計();
        println!(
            "  更新後の判定 Σλ_n={:.6e} ‖Σλ_t‖={:.6e} 円錐の半径={円錐の半径:.6e} 内側か={}",
            連立.更新後の法線の乗数の合計(),
            連立.更新後の接線の合力の大きさ(),
            連立.更新後の接線の合力の大きさ() <= 円錐の半径,
        );
    }
}
