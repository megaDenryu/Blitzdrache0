//! 記録のための細分1本(判断13の原因の分離のための計器)。担当するのは、予測と接触点集合と履歴の併走までを本番と
//! 同じ順で行い、位置の反復の中の3つの地点(非貫通の前・非貫通の後・接線解の後)で記録を綴ることである。
//! 細分の残り(速度の再構成・速度段階・履歴の書き戻し)は行わない。記録はその細分の反復の内側だけを見るためであり、
//! この場面はここで捨てるからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」

#![cfg(test)]

use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::scene::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_body::一刻みの入力;
use crate::rigid_xpbd::予測の状態;

impl 一つの箱と静的な直方体の場面 {
    // 次の1細分を、位置の反復の3つの地点で記録しながら回す。細分の結果は場面へ書き戻さない。
    pub(super) fn 次の細分の反復を記録する(&mut self, 見出し: &str) {
        let (_, mut 予測, _) = self
            .予測器
            .動的剛体を予測する(&self.箱の配置, &self.箱の運動状態, &self.箱の質量特性, &一刻みの入力::無し());
        let mut バッチ = self.接触拘束のバッチを組む(&予測);
        let _ = self.履歴の記録を引き継ぐ(&mut バッチ);
        for 反復番号 in 0..self.解く品質.位置の反復回数() {
            self.記録の一地点を綴る(見出し, 反復番号, "非貫通の前", バッチ.剛体と静的世界の接触拘束(), &予測);
            予測 = self.非貫通だけを解く(&mut バッチ, 予測);
            self.記録の一地点を綴る(見出し, 反復番号, "非貫通の後", バッチ.剛体と静的世界の接触拘束(), &予測);
            予測 = self.静止摩擦だけを解く(&mut バッチ, 予測);
            self.記録の一地点を綴る(見出し, 反復番号, "接線解の後", バッチ.剛体と静的世界の接触拘束(), &予測);
        }
    }

    fn 非貫通だけを解く(&self, バッチ: &mut 接触拘束の二つのバッチ, 予測: 予測の状態) -> 予測の状態 {
        let mut 予測 = 予測;
        for 集合の番号 in 0..バッチ.剛体と静的世界の接触点集合の数() {
            let 接触点集合 = バッチ.剛体と静的世界の接触点集合を反復のために借りる(集合の番号);
            予測 = self.接触点集合の非貫通を同時に解く(接触点集合, 予測);
        }
        予測
    }

    fn 静止摩擦だけを解く(&self, バッチ: &mut 接触拘束の二つのバッチ, 予測: 予測の状態) -> 予測の状態 {
        let mut 予測 = 予測;
        for 集合の番号 in 0..バッチ.剛体と静的世界の接触点集合の数() {
            let 接触点集合 = バッチ.剛体と静的世界の接触点集合を反復のために借りる(集合の番号);
            予測 = self.接触点集合の静止摩擦を同時に解く(接触点集合, 予測);
        }
        予測
    }
}
