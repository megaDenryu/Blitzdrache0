//! 記録の1地点で接触点1つから読む量(判断13の原因の分離のための計器)。担当するのは、拘束といまの予測の配置から、
//! 特徴の識別・法線の有効集合に入るか・隔たり・錨からの接線変位・法線の乗数・接線の乗数・接触点の世界位置を読むことである。
//! 集合の単位の集計は`manifold_observation`が持つ。合否は判定せず、値を読むだけである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_math::{メートル, ワールド, 位置, 変位};

use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::feature_identity::接触の特徴の識別;
use crate::contact::static_friction::接線のラグランジュ乗数;
use crate::rigid_xpbd::姿勢自由度の参加者;
use crate::xpbd::ラグランジュ乗数;

/// 記録の1地点で接触点1つから読んだ量。
pub(super) struct 接触点の観測 {
    pub(super) 特徴の識別: 接触の特徴の識別,
    pub(super) 法線の有効集合に入るか: bool,
    pub(super) 隔たり: メートル,
    pub(super) 錨からの接線変位: 変位<ワールド>,
    pub(super) 法線の乗数: ラグランジュ乗数,
    pub(super) 接線の乗数: 接線のラグランジュ乗数,
    pub(super) 接触点の世界位置: 位置<ワールド>,
}

impl 接触点の観測 {
    /// 拘束といまの予測の配置から読む。法線の有効集合の判定は`法線の有効集合`の開始の定義と同じ式である。
    pub(super) fn 拘束から読む(拘束: &剛体と静的世界の接触拘束, 剛体: &姿勢自由度の参加者) -> Self {
        let 隔たり = 拘束.同時解法の一行にする(剛体).隔たり();
        let 法線の乗数 = 拘束.法線のラグランジュ乗数();
        let 錨 = 拘束.静止摩擦の錨();
        let 錨の世界位置 = 剛体.配置().局所点の世界位置(錨.第1の参加者の重心局所点());
        Self {
            特徴の識別: 拘束.引数().特徴の識別,
            法線の有効集合に入るか: 隔たり < メートル::生成する(0.0) || 法線の乗数 > ラグランジュ乗数::零(),
            隔たり,
            錨からの接線変位: (錨の世界位置 - 錨.第2の参加者から見た点()).方向の成分を除く(拘束.引数().接触法線),
            法線の乗数,
            接線の乗数: 拘束.静止摩擦の解の状態().接線のラグランジュ乗数(),
            接触点の世界位置: 拘束.引数().静的世界側の接触点,
        }
    }
}
