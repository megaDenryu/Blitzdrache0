//! 記録する1つの場合と、計器が見る場合の並び(判断13の原因の分離のための計器)。担当するのは、鉛直軸まわりの回しと
//! 傾きの正接から坂の場面の条件を組むことと、その条件で接触点集合が初めて滑走中と印される細分を探すことである。
//! 走査(`mod`)から分けているのは、こちらが1つの場合を所有し、あちらが並びを回して綴る走査だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use std::f32::consts::PI;

use super::super::super::friction_coefficient::摩擦係数;
use super::super::residual_separation::場面の残差の分離;
use super::super::slope_fixture::坂の場面を組む;
use super::super::slope_geometry::坂の場面の条件;
use super::super::static_friction_method::場面の静止摩擦の解き方;
use super::静止摩擦係数の値;

// 走査する傾きの正接を百分の一刻みで作るときの、両端(静止摩擦係数0.6の3分の2から係数そのものまで)。
const 走査する正接の百分率の下端: u16 = 40;
const 走査する正接の百分率の上端: u16 = 60;

/// 計器が見る1つの場合。坂の傾きと鉛直軸まわりの回しの組と、綴りに使う見出しを持つ。
pub(super) struct 記録する一つの場合 {
    pub(super) 見出し: String,
    pub(super) 鉛直軸まわりの回し: f32,
    pub(super) 傾きの正接: f32,
}

impl 記録する一つの場合 {
    pub(super) fn 回しと正接から生成する(鉛直軸まわりの回し: f32, 傾きの正接: f32) -> Self {
        Self {
            見出し: format!("回し{鉛直軸まわりの回し:.3}_正接{傾きの正接}"),
            鉛直軸まわりの回し,
            傾きの正接,
        }
    }

    /// 保持と滑走の境界の周囲で、方向ごとの差が残っている5つの組。45度の正接0.53だけが600刻みで保持している。
    pub(super) fn 内訳を記録する並び() -> Vec<Self> {
        [(PI / 4.0, 0.52), (PI / 4.0, 0.53), (PI / 4.0, 0.54), (0.0, 0.50), (0.0, 0.51)]
            .iter()
            .map(|(回し, 正接)| Self::回しと正接から生成する(*回し, *正接))
            .collect()
    }

    /// 3つの回しについて、傾きの正接を百分の一刻みで振った並び。境界が摩擦の境界かどうかを見るための走査である。
    pub(super) fn 境界の周囲を走査する並び() -> Vec<Self> {
        let mut 並び = Vec::new();
        for 回し in [0.0, PI / 6.0, PI / 4.0] {
            for 百分率 in 走査する正接の百分率の下端..=走査する正接の百分率の上端 {
                並び.push(Self::回しと正接から生成する(回し, f32::from(百分率) / 100.0));
            }
        }
        並び
    }

    pub(super) fn 坂の場面の条件を組む(&self) -> 坂の場面の条件 {
        坂の場面の条件 {
            傾きの正接: self.傾きの正接,
            鉛直軸まわりの回し: self.鉛直軸まわりの回し,
            静止摩擦係数: 摩擦係数::生成する(静止摩擦係数の値).unwrap(),
            動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
            下り向きの初速: 0.0,
            静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
            残差の分離: 場面の残差の分離::残差の変化を速度から除く,
        }
    }

    /// 接触点集合が初めて滑走中と印された細分の番号(0から数える)。上限まで見つからなければ無しである。
    pub(super) fn 円錐を初めて超えた細分の番号(&self, 探す上限: usize) -> Option<usize> {
        let mut 場面 = 坂の場面を組む(&self.坂の場面の条件を組む());
        for 番号 in 0..探す上限 {
            場面.一細分進める();
            if 場面.直前の細分の観測.滑走中の接触点の数 > 0 {
                return Some(番号);
            }
        }
        None
    }

    /// 指定の細分まで進めてから、その次の1本の位置の反復を綴る。
    pub(super) fn 細分の内訳を綴る(&self, 番号: usize) {
        let mut 場面 = 坂の場面を組む(&self.坂の場面の条件を組む());
        場面.細分を進める(番号);
        場面.次の細分の反復を記録する(&format!("{}_細分{番号}", self.見出し));
    }
}
