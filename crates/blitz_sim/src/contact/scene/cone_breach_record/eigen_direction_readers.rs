//! 記録の1地点の固有分解の内訳を読む口(判断13の原因の分離のための計器)。担当するのは、固有の向きごとに固有値・
//! 固有値の最大に対する比・右辺の射影 β_k・許容差の積み上がり δ_k・擬似逆が捨てたかどうかを返すことである。
//! 連立を組む工程(`tangential_system_observation`)から分けているのは、この読み取りが分解・右辺・行ごとの許容差・
//! 行の数の4つだけに触れ、行列と解には触れないためである。捨てた判定は本番の求解と同じ口を呼んで導く。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::tangential_system_observation::接線の連立の観測;
use crate::contact::symmetric_system::擬似逆が固有の向きを捨てた理由;

impl 接線の連立の観測 {
    /// 第k番の固有値と、固有値の最大に対する比。
    pub(super) fn 固有値と比(&self, k: usize) -> (f32, f32) {
        let 最大 = (0..self.行の数).map(|番号| self.分解.第k番の固有値(番号)).fold(0.0, f32::max);
        let 固有値 = self.分解.第k番の固有値(k);
        (固有値, if 最大 > 0.0 { 固有値 / 最大 } else { 0.0 })
    }

    /// 第k番の固有ベクトルへの右辺の射影 β_k = v_kᵀ b。
    pub(super) fn 右辺の射影(&self, k: usize) -> f32 {
        (0..self.行の数).map(|i| self.分解.第k番の固有ベクトルの成分(k, i) * self.右辺[i]).sum()
    }

    /// 第k番の固有ベクトルの向きへ行ごとの許容差が積み上がる大きさ δ_k = √(Σ_i (v_ik δ_i)²)。
    pub(super) fn 許容差の射影(&self, k: usize) -> f32 {
        (0..self.行の数)
            .map(|i| {
                let 成分 = self.分解.第k番の固有ベクトルの成分(k, i) * self.行ごとの解けたと見なす許容差[i];
                成分 * 成分
            })
            .sum::<f32>()
            .sqrt()
    }

    /// 擬似逆が第k番の固有の向きを捨てたかと、捨てたならその理由。本番の求解と同じ判定を呼ぶ。
    pub(super) fn 第k番の向きを捨てた理由(&self, k: usize) -> 擬似逆が固有の向きを捨てた理由 {
        self.分解.第k番の向きを捨てた理由(k, &self.右辺, &self.行ごとの解けたと見なす許容差)
    }
}
