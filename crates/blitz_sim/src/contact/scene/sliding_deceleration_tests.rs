//! 滑走中の坂の箱の減速度で判断14の動摩擦の定量の基準を固定する試験。担当するのは、動摩擦係数0.1から0.55の
//! どれでも減速度が g(sinθ − μ_d cosθ) と相対誤差1パーセント以内で一致することである。
//! 坂の保持の試験(`slope_tests`)から分けているのは、こちらが滑走中の抵抗を測る別の基準であり、動摩擦係数を
//! 振って測る材料を持つためである。誤差が動摩擦係数とともに増えないことが、位置の静止摩擦と速度の動摩擦が
//! 二重に効いていないことの検査になる(二重に効くと実効の摩擦係数が上がり、誤差が μ_d とともに増える)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

#![allow(clippy::unwrap_used)]

use super::super::friction_coefficient::摩擦係数;
use super::slope_fixture::坂の場面を組む;
use super::slope_geometry::{坂の場面の条件, 滑走の加速度};
use super::static_friction_method::場面の静止摩擦の解き方;

const 滑る傾きの正接: f32 = 0.9;
const 静止摩擦係数の値: f32 = 0.6;
const 下り向きの初速: f32 = 1.0;
const 測り始めるまでの細分数: usize = 60; // 初めの食い込みの解消と接触の落ち着きに要る細分数
const 測る細分数: usize = 240;
const 測る秒数: f32 = 0.5; // 測る細分数 ÷ (1細分の刻み幅 1/480秒)
const 許す相対誤差: f32 = 0.01;
const 振る動摩擦係数: [f32; 5] = [0.1, 0.2, 0.3, 0.4, 0.55];

fn 測った減速度の相対誤差(動摩擦係数の値: f32) -> f32 {
    let 条件 = 坂の場面の条件 {
        傾きの正接: 滑る傾きの正接,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(静止摩擦係数の値).unwrap(),
        動摩擦係数: 摩擦係数::生成する(動摩擦係数の値).unwrap(),
        下り向きの初速,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    };
    let mut 場面 = 坂の場面を組む(&条件);
    場面.細分を進める(測り始めるまでの細分数);
    let 初めの速さ = 場面.下り向きの速さ(&条件);
    場面.細分を進める(測る細分数);
    let 測った加速度 = (場面.下り向きの速さ(&条件) - 初めの速さ) / 測る秒数;
    let 解析の加速度 = 滑走の加速度(滑る傾きの正接, 動摩擦係数の値);
    (測った加速度 - 解析の加速度).abs() / 解析の加速度
}

#[test]
fn 滑走中の減速度は動摩擦係数を振っても解析値と一パーセント以内で一致する() {
    for 動摩擦係数の値 in 振る動摩擦係数 {
        let 相対誤差 = 測った減速度の相対誤差(動摩擦係数の値);
        assert!(
            相対誤差 <= 許す相対誤差,
            "動摩擦係数{動摩擦係数の値}の滑走の加速度が解析値と{相対誤差}ずれた"
        );
    }
}
