//! 坂の場面の組み立ての指定(判断13・判断14の検収と、Issue #59の数値契約の診断)。位置の反復回数・世界内の平行移動・
//! 試験の許容差の当て方・一刻みの細分数・重力の5つを1つに束ねる。場面の組み立て(`slope_fixture`)から分けているのは、
//! 組み立ての口が既定から1つか2つだけ変えた指定を受け取る形であり、5つを引数で並べると呼び出し側が毎回全部を
//! 書くことになるためである。既定の値はこの型が持ち、計器は既定から要る欄だけを書き換える。
//! 細分数を列挙で持つのは、刻み幅の綴り(1/480秒・1/960秒)を本数と対にして1箇所へ閉じるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, メートル毎秒毎秒, ワールド, 方向, 秒};

use super::super::normal_tangential_system::試験の許容差の当て方;
use super::slope_geometry::重力の大きさ;
use crate::constraint_graph::一様な加速度;
use crate::xpbd::刻み幅;

// 判断19の品質の設定。位置の反復回数2の由来は正本の判断19の実装の細目にある。
pub(super) const 既定の位置の反復回数: u32 = 2;

/// 基本刻み1/60秒を分ける細分の本数。場面の試験の既定は8本であり、16本は本番の設定(判断19)と同じ刻み幅である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) enum 坂の場面の一刻みの細分数 {
    八本,
    十六本,
}

impl 坂の場面の一刻みの細分数 {
    pub(super) fn 本数(&self) -> usize {
        match self {
            Self::八本 => 8,
            Self::十六本 => 16,
        }
    }

    pub(super) fn 細分の刻み幅の秒(&self) -> f32 {
        match self {
            Self::八本 => 1.0 / 480.0,
            Self::十六本 => 1.0 / 960.0,
        }
    }

    pub(super) fn 細分の刻み幅(&self) -> 刻み幅 {
        刻み幅::生成する(秒::生成する(self.細分の刻み幅の秒())).unwrap()
    }
}

/// 坂の場面を組み立てる指定。
pub(super) struct 坂の場面の組み立ての指定 {
    pub(super) 位置の反復回数: u32,
    pub(super) 法線の向きへ動かす長さ: メートル,
    pub(super) 試験の許容差の当て方: 試験の許容差の当て方,
    pub(super) 一刻みの細分数: 坂の場面の一刻みの細分数,
    pub(super) 重力: 一様な加速度,
}

impl 坂の場面の組み立ての指定 {
    /// 検収の既定(位置の反復回数2・平行移動なし・本番と同じ許容差・8細分・鉛直下向きの重力)。
    pub(super) fn 既定() -> Self {
        Self {
            位置の反復回数: 既定の位置の反復回数,
            法線の向きへ動かす長さ: メートル::生成する(0.0),
            試験の許容差の当て方: 試験の許容差の当て方::本番と同じ(),
            一刻みの細分数: 坂の場面の一刻みの細分数::八本,
            重力: 鉛直下向きの重力(),
        }
    }
}

/// 大きさ g の鉛直下向きの重力。
pub(super) fn 鉛直下向きの重力() -> 一様な加速度 {
    一様な加速度::成分から生成する(
        メートル毎秒毎秒::生成する(0.0),
        メートル毎秒毎秒::生成する(-重力の大きさ),
        メートル毎秒毎秒::生成する(0.0),
    )
}

/// 大きさ g で指定の向きへ掛かる重力。坂の面の法線の逆向きへ掛けると接線の荷重が無い休止の場面を作れる。
pub(super) fn 向きへ掛かる重力(向き: 方向<ワールド>) -> 一様な加速度 {
    一様な加速度::成分から生成する(
        メートル毎秒毎秒::生成する(重力の大きさ * 向き.x()),
        メートル毎秒毎秒::生成する(重力の大きさ * 向き.y()),
        メートル毎秒毎秒::生成する(重力の大きさ * 向き.z()),
    )
}
