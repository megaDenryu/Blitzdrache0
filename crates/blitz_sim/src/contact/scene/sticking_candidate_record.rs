//! 粘着の候補が細分ごとにどう決着したかを綴る計器(判断13の原因の分離)。担当するのは、傾きの正接を振って、
//! 接触点集合が初めて滑走中と印される細分の番号と、そこまでに粘着の候補が解けなかった細分の延べ数を並べることである。
//! 解けなかった延べ数を一緒に見るのは、円錐を超えて滑走へ移ったのか、相補条件を満たす有効集合が無かったのか、
//! 表現の精度が足りずに法線だけの連立へ落ちたのかを分けるためである。3つは同じ「保持しない」に見える。
//! 合否は判定しない。判定する検査は`slope_tests`と`sticking_candidate_tests`が持つ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use std::f32::consts::PI;

use super::super::friction_coefficient::摩擦係数;
use super::slope_fixture::坂の場面を組む;
use super::slope_geometry::坂の場面の条件;
use super::static_friction_method::場面の静止摩擦の解き方;

const 振る傾きの正接: [f32; 5] = [0.40, 0.48, 0.50, 0.55, 0.61];
const 見る細分数: usize = 4800; // 600刻み。受入条件が保持を見る長さと同じである

fn 走査する条件(傾きの正接: f32, 鉛直軸まわりの回し: f32) -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接,
        鉛直軸まわりの回し,
        静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    }
}

// 初めて滑走中と印された細分の番号と、見た範囲で粘着の候補が解けなかった接触点集合の延べ数。
fn 初めて滑走した細分と解けなかった延べ数(条件: &坂の場面の条件) -> (Option<usize>, usize) {
    let mut 場面 = 坂の場面を組む(条件);
    let mut 初めて滑走した細分 = None;
    for 番号 in 0..見る細分数 {
        場面.一細分進める();
        if 初めて滑走した細分.is_none() && 場面.直前の細分の観測.滑走中の接触点の数 > 0 {
            初めて滑走した細分 = Some(番号);
        }
    }
    (初めて滑走した細分, 場面.粘着の候補が解けなかった接触点集合の延べ数)
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 粘着の候補の決着を傾きごとに記録する() {
    println!("傾きの正接 | 回し | 初めて滑走した細分 | 解けなかった延べ数");
    for 正接 in 振る傾きの正接 {
        for 回し in [0.0, PI / 6.0, PI / 4.0] {
            let (滑走, 解けなかった) = 初めて滑走した細分と解けなかった延べ数(&走査する条件(正接, 回し));
            println!("{正接} | {回し:.3} | {滑走:?} | {解けなかった}");
        }
    }
}
