//! 場面の細分の中の静止摩擦の射影(判断13の接触点集合の単位の試験専用の実装)。担当するのは、接触点集合1つの
//! 全部の点を仮の配置へ射影し、接線の乗数の合力でクーロン円錐を1度だけ判定し、内側なら一括で確定し、超えたら
//! 全部を捨てて集合ごと滑走中と印すことである。非貫通の反復(`substep_solve`)から分けているのは、こちらが
//! 接触点集合の単位で仮の配置を作って捨てるという別の工程だからである。
//! 法線反力を解放された点の扱いは`接触点の仮の接線の乗数`が決める。剛体どうしの本番の工程も同じ型を読む契約である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_collision::contact_set::接触点の上限;

use super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::super::static_friction::接線のラグランジュ乗数;
use super::super::static_friction::接触点の仮の接線の乗数;
use super::super::static_friction::接触点集合の静止摩擦の仮の集計;
use super::super::static_friction::静止摩擦の一回の仮の射影の結果;
use super::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_xpbd::{予測の状態, 姿勢自由度の参加者};

impl 一つの箱と静的な直方体の場面 {
    // 接触点集合1つの静止摩擦を射影する。円錐の内側なら仮の配置をそのまま返し、超えたら射影の前の配置へ戻す。
    // 注意: 仮の乗数の受け皿の長さは接触点集合が持てる接触点の上限である。これを超える集合は衝突数学層の不変条件の破れであり、
    // 添字の範囲外として落ちる。
    pub(super) fn 接触点集合の静止摩擦を射影する(
        &self,
        接触点集合: &mut [剛体と静的世界の接触拘束],
        射影の前の予測: 予測の状態,
    ) -> 予測の状態 {
        let Some(先頭) = 接触点集合.first() else {
            return 射影の前の予測;
        };
        if 先頭.静止摩擦の解の状態().滑走中か() {
            return 射影の前の予測;
        }
        let 接触物性 = 先頭.引数().接触物性;
        let mut 仮の予測 = 射影の前の予測;
        let mut 集計 = 接触点集合の静止摩擦の仮の集計::空();
        let 空の仮の乗数 = 接触点の仮の接線の乗数::集合が円錐の内側なら確定する(接線のラグランジュ乗数::零());
        let mut 仮の接線の乗数 = [空の仮の乗数; 接触点の上限];
        for (添字, 拘束) in 接触点集合.iter().enumerate() {
            let 参加者 = 姿勢自由度の参加者::動的(*仮の予測.配置(), &self.箱の質量特性);
            let 結果 = 拘束.静止摩擦を一回仮に射影する(&参加者);
            if let 静止摩擦の一回の仮の射影の結果::接線を戻す補正を求めた { 補正a, .. } = 結果 {
                仮の予測 = 仮の予測.補正を適用する(&補正a);
            }
            仮の接線の乗数[添字] = 接触点の仮の接線の乗数::射影の結果と解の状態から決める(結果, 拘束.静止摩擦の解の状態());
            集計 = 集計.一点の仮の乗数を足した集計(拘束.法線のラグランジュ乗数(), 仮の接線の乗数[添字].確定する接線の乗数());
        }
        if !集計.円錐の内側か(接触物性) {
            for (添字, 拘束) in 接触点集合.iter_mut().enumerate() {
                拘束.接触点集合が滑走中になったと印す();
                if 仮の接線の乗数[添字].集合が円錐を超えても解放するか() {
                    拘束.静止摩擦の接線の乗数を零へ解放する();
                }
            }
            return 射影の前の予測;
        }
        for (添字, 拘束) in 接触点集合.iter_mut().enumerate() {
            拘束.静止摩擦の仮の乗数を確定する(仮の接線の乗数[添字].確定する接線の乗数());
        }
        仮の予測
    }
}
