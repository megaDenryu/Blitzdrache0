//! 場面の細分の中の静止摩擦の同時解法(判断13の接触点集合の単位の試験専用の実装)。担当するのは、接触点集合1つの
//! 全部の点の接線を1つの連立として解き、点ごとの補正を合計してから配置へ1度だけ適用し、接線の乗数の合力で
//! クーロン円錐を1度だけ判定し、内側なら一括で確定し、超えたら全部を捨てて集合ごと滑走中と印すことである。
//! 非貫通の同時解法(`substep_non_penetration`)から分けているのは、こちらが接線の連立と円錐の判定という別の工程
//! だからである。点ごとに順に射影する反証は`substep_static_friction_sequential`が持つ。
//! 法線反力を解放された点の扱いは`接触点の仮の接線の乗数`が決める。剛体どうしの本番の工程も同じ型を読む契約である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_collision::contact_set::接触点の上限;

use super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::super::static_friction::接線のラグランジュ乗数;
use super::super::static_friction::接触点の仮の接線の乗数;
use super::super::static_friction::接触点集合の静止摩擦の仮の集計;
use super::super::static_friction::接触点集合の静止摩擦の連立;
use super::super::static_friction::静止摩擦の連立へ点を入れた結果;
use super::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_xpbd::{予測の状態, 姿勢自由度の参加者, 姿勢自由度の補正};

impl 一つの箱と静的な直方体の場面 {
    // 接触点集合1つの接線を同時に解く。円錐の内側なら補正を適用した配置を、超えたら射影の前の配置を返す。
    // 注意: 受け皿の長さは接触点集合が持てる接触点の上限である。これを超える集合は衝突数学層の不変条件の破れであり、
    // 添字の範囲外として落ちる。
    pub(super) fn 接触点集合の静止摩擦を同時に解く(
        &self,
        接触点集合: &mut [剛体と静的世界の接触拘束],
        射影の前の予測: 予測の状態,
    ) -> 予測の状態 {
        let Some(先頭) = 接触点集合.first() else {
            return 射影の前の予測;
        };
        if 先頭.静止摩擦の解の状態().滑走中か() {
            return 射影の前の予測;
        }
        let 接触物性 = 先頭.引数().接触物性;
        let 参加者 = 姿勢自由度の参加者::動的(*射影の前の予測.配置(), &self.箱の質量特性);
        let mut 点を入れた結果 = [静止摩擦の連立へ点を入れた結果::両方が動かせない; 接触点の上限];
        let mut 連立 = 接触点集合の静止摩擦の連立::点の数から空で始める(接触点集合.len());
        for (添字, 拘束) in 接触点集合.iter().enumerate() {
            点を入れた結果[添字] = 拘束.静止摩擦の連立へ一行を積む(添字, &mut 連立, &参加者);
        }
        let 同時解 = 連立.同時に解く();
        let 空の仮の乗数 = 接触点の仮の接線の乗数::集合が円錐の内側なら確定する(接線のラグランジュ乗数::零());
        let mut 仮の接線の乗数 = [空の仮の乗数; 接触点の上限];
        let mut 集計 = 接触点集合の静止摩擦の仮の集計::空();
        let mut 補正の合計 = 姿勢自由度の補正::零();
        for (添字, 拘束) in 接触点集合.iter().enumerate() {
            let 乗数の増分 = 同時解.一点の乗数の増分(添字);
            let 積んだ行 = 連立.一行を読む(添字);
            仮の接線の乗数[添字] = 接触点の仮の接線の乗数::積んだ行と乗数の増分から決める(
                点を入れた結果[添字],
                拘束.静止摩擦の解の状態(),
                積んだ行,
                乗数の増分,
            );
            集計 = 集計.一点の仮の乗数を足した集計(拘束.法線のラグランジュ乗数(), 仮の接線の乗数[添字].確定する接線の乗数());
            if let Some(一行) = 積んだ行 {
                補正の合計 = 補正の合計.合わせる(&一行.乗数の増分を第1の参加者の補正へ分配する(乗数の増分));
            }
        }
        if !集計.円錐の内側か(接触物性) {
            self.接触点集合を滑走中にする(接触点集合, &仮の接線の乗数);
            return 射影の前の予測;
        }
        for (添字, 拘束) in 接触点集合.iter_mut().enumerate() {
            拘束.静止摩擦の仮の乗数を確定する(仮の接線の乗数[添字].確定する接線の乗数());
        }
        射影の前の予測.補正を適用する(&補正の合計)
    }

    // 円錐を超えた集合の後始末。仮の補正は捨て、滑走中と印し、法線反力の無い点の乗数だけは零へ確定する。
    pub(super) fn 接触点集合を滑走中にする(
        &self,
        接触点集合: &mut [剛体と静的世界の接触拘束],
        仮の接線の乗数: &[接触点の仮の接線の乗数; 接触点の上限],
    ) {
        for (添字, 拘束) in 接触点集合.iter_mut().enumerate() {
            拘束.接触点集合が滑走中になったと印す();
            if 仮の接線の乗数[添字].集合が円錐を超えても解放するか() {
                拘束.静止摩擦の接線の乗数を零へ解放する();
            }
        }
    }
}
