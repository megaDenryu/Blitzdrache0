//! 場面の細分の中の静止摩擦の同時解法(判断13の接触点集合の単位の試験専用の実装)。担当するのは、接触点集合1つの
//! 法線の行と接線の行を1つの連立として解き、点ごとの補正を合計してから配置へ1度だけ適用し、更新後の乗数で
//! クーロン円錐を1度だけ判定し、内側なら配置と法線の乗数と接線の乗数を一括で確定し、超えたら法線の荷重の
//! 移し替えごと全部を捨てて集合ごと滑走中と印すことである。
//! 非貫通の同時解法(`substep_non_penetration`)から分けているのは、こちらが混合の連立と円錐の判定という別の工程
//! だからである。点ごとに順に射影する反証は`substep_static_friction_sequential`が持つ。
//! 法線の有効集合から外れた点は法線反力が無い点として扱い、接線の乗数を零へ解放する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_collision::contact_set::接触点の上限;

use super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::super::normal_tangential_system::{接触点集合の法線と接線の同時解, 接触点集合の法線と接線の連立};
use super::super::static_friction::接触点の仮の接線の乗数;
use super::super::static_friction::接触点集合の仮の乗数の集まり;
use super::super::static_friction::静止摩擦の連立へ点を入れた結果;
use super::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_xpbd::{予測の状態, 姿勢自由度の参加者};

impl 一つの箱と静的な直方体の場面 {
    // 接触点集合1つの法線と接線を同時に解く。円錐の内側なら補正を適用した配置を、超えたら射影の前の配置を返す。
    // 注意: 受け皿の長さは接触点集合が持てる接触点の上限である。これを超える集合は衝突数学層の不変条件の破れであり、
    // 添字の範囲外として落ちる。
    pub(super) fn 接触点集合の静止摩擦を同時に解く(
        &self,
        接触点集合: &mut [剛体と静的世界の接触拘束],
        射影の前の予測: 予測の状態,
    ) -> 予測の状態 {
        let Some(先頭) = 接触点集合.first() else {
            return 射影の前の予測;
        };
        if 先頭.静止摩擦の解の状態().滑走中か() {
            return 射影の前の予測;
        }
        let 接触物性 = 先頭.引数().接触物性;
        let 参加者 = 姿勢自由度の参加者::動的(*射影の前の予測.配置(), &self.箱の質量特性);
        let (連立, 点を入れた結果) = self.法線と接線の連立を組む(接触点集合, &参加者);
        let 同時解 = 連立.同時に解く();
        let 仮の乗数 = 仮の乗数の集まりを求める(接触点集合, &連立, &同時解, &点を入れた結果);
        if !仮の乗数.円錐の内側か(接触物性) {
            self.接触点集合を滑走中にする(接触点集合, &参加者, &仮の乗数);
            return 射影の前の予測;
        }
        for (添字, 拘束) in 接触点集合.iter_mut().enumerate() {
            拘束.法線と接線の連立の法線の乗数の増分を取り込む(&参加者, 同時解.一点の法線の乗数の増分(添字));
            拘束.静止摩擦の仮の乗数を確定する(仮の乗数.一点の仮の接線の乗数(添字).確定する接線の乗数());
        }
        射影の前の予測.補正を適用する(&連立.第1の参加者への補正の合計(&同時解))
    }

    // 接触点集合の全部の点から法線の行と接線の行を積んだ連立と、点ごとの接線の行の結果。
    fn 法線と接線の連立を組む(
        &self,
        接触点集合: &[剛体と静的世界の接触拘束],
        参加者: &姿勢自由度の参加者,
    ) -> (接触点集合の法線と接線の連立, [静止摩擦の連立へ点を入れた結果; 接触点の上限]) {
        let mut 点を入れた結果 = [静止摩擦の連立へ点を入れた結果::両方が動かせない; 接触点の上限];
        let mut 連立 = 接触点集合の法線と接線の連立::点の数から空で始める(接触点集合.len());
        for (添字, 拘束) in 接触点集合.iter().enumerate() {
            拘束.法線と接線の連立へ法線の一行を積む(添字, &mut 連立, 参加者);
            点を入れた結果[添字] = 拘束.法線と接線の連立へ接線の一行を積む(添字, &mut 連立, 参加者);
        }
        (連立, 点を入れた結果)
    }

    // 円錐を超えた集合の後始末。仮の補正と法線の荷重の移し替えは捨て、滑走中と印し、法線反力の無い点の乗数だけは零へ確定する。
    pub(super) fn 接触点集合を滑走中にする(
        &self,
        接触点集合: &mut [剛体と静的世界の接触拘束],
        参加者: &姿勢自由度の参加者,
        仮の乗数: &接触点集合の仮の乗数の集まり,
    ) {
        for (添字, 拘束) in 接触点集合.iter_mut().enumerate() {
            拘束.接触点集合が滑走中になったと印す(参加者);
            if 仮の乗数.一点の仮の接線の乗数(添字).集合が円錐を超えても解放するか() {
                拘束.静止摩擦の接線の乗数を零へ解放する();
            }
        }
    }
}

// 解いた増分から点ごとの仮の接線の乗数と円錐の判定の集計を組む。法線の有効集合から外れた点は、その乗数を支える
// 法線反力がもう無いため、接線の行を積んでいても法線反力が無い点として扱う。
fn 仮の乗数の集まりを求める(
    接触点集合: &[剛体と静的世界の接触拘束],
    連立: &接触点集合の法線と接線の連立,
    同時解: &接触点集合の法線と接線の同時解,
    点を入れた結果: &[静止摩擦の連立へ点を入れた結果; 接触点の上限],
) -> 接触点集合の仮の乗数の集まり {
    let mut 仮の乗数 = 接触点集合の仮の乗数の集まり::空から始める();
    for (添字, 拘束) in 接触点集合.iter().enumerate() {
        let 点の結果 = if 同時解.一点の法線の行が有効か(添字) {
            点を入れた結果[添字]
        } else {
            静止摩擦の連立へ点を入れた結果::法線反力が無い
        };
        仮の乗数.一点を足す(
            添字,
            接触点の仮の接線の乗数::積んだ行の向きと乗数の増分から決める(
                点の結果,
                拘束.静止摩擦の解の状態(),
                連立.接線の一行を読む(添字).map(|一行| 一行.接線の向き()),
                同時解.一点の接線の乗数の増分(添字),
            ),
            拘束.法線のラグランジュ乗数() + 同時解.一点の法線の乗数の増分(添字),
        );
    }
    仮の乗数
}
