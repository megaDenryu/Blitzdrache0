//! 場面の細分の中の位置の解き方(判断19の反復の試験専用の実装)。担当するのは、履歴の併走の結果を拘束へ配ることと、
//! 予測の直後の法線相対速度を測ることと、反復1回(全部の非貫通→全部の静止摩擦)を回すことである。
//! 速度段階の巡回は`substep_velocity_stage`が持つ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::メートル毎秒;

use super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::super::contact_batches::接触拘束の二つのバッチ;
use super::super::history::接触の対応付け;
use super::super::non_penetration::非貫通の一回の射影の結果;
use super::super::static_friction::静止摩擦の一回の射影の結果;
use super::super::velocity_stage::接触点の法線の相対速度を求める;
use super::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_body::運動状態;
use crate::rigid_xpbd::{予測の状態, 姿勢自由度の参加者};

impl 一つの箱と静的な直方体の場面 {
    // 併走の対応付けを拘束へ配り、開始した接触点の数を返す。
    pub(super) fn 履歴の記録を引き継ぐ(&mut self, バッチ: &mut 接触拘束の二つのバッチ) -> usize {
        let 持ち込む項目: Vec<_> = バッチ
            .剛体と静的世界の接触拘束()
            .iter()
            .map(剛体と静的世界の接触拘束::併走へ持ち込む履歴の項目)
            .collect();
        let 対応付け: Vec<_> = self.履歴.新しい細分の接触と併走する(&持ち込む項目).unwrap().対応付け一覧().to_vec();
        for (拘束, 対応) in バッチ.剛体と静的世界の接触拘束を反復のために借りる().iter_mut().zip(&対応付け) {
            if let 接触の対応付け::継続 { 引き継いだ記録 } = 対応 {
                拘束.継続の記録を引き継ぐ(*引き継いだ記録);
            }
        }
        対応付け.iter().filter(|対応| !対応.継続か()).count()
    }

    pub(super) fn 予測の前の法線相対速度を測る(
        &self,
        バッチ: &接触拘束の二つのバッチ,
        予測: &予測の状態,
        予測の運動状態: 運動状態,
    ) -> Vec<メートル毎秒> {
        let 参加者 = 姿勢自由度の参加者::動的(*予測.配置(), &self.箱の質量特性);
        バッチ
            .剛体と静的世界の接触拘束()
            .iter()
            .map(|拘束| {
                接触点の法線の相対速度を求める(
                    拘束.速度段階の剛体の参加点(&参加者, 予測の運動状態),
                    拘束.速度段階の静的世界の参加点(),
                    拘束.引数().接触法線,
                )
            })
            .collect()
    }

    // 判断19の反復1回。拘束の族の順に、まず全部の非貫通を、次に全部の静止摩擦を射影する。
    pub(super) fn 一回反復する(&self, バッチ: &mut 接触拘束の二つのバッチ, 予測: 予測の状態) -> 予測の状態 {
        let mut 予測 = 予測;
        for 拘束 in バッチ.剛体と静的世界の接触拘束を反復のために借りる() {
            let 参加者 = 姿勢自由度の参加者::動的(*予測.配置(), &self.箱の質量特性);
            if let 非貫通の一回の射影の結果::補正した { 補正a, .. } = 拘束.一回射影する(&参加者) {
                予測 = 予測.補正を適用する(&補正a);
            }
        }
        if self.静止摩擦の位置拘束を外すか {
            return 予測;
        }
        for 拘束 in バッチ.剛体と静的世界の接触拘束を反復のために借りる() {
            let 参加者 = 姿勢自由度の参加者::動的(*予測.配置(), &self.箱の質量特性);
            if let 静止摩擦の一回の射影の結果::円錐の内側で保持した { 補正a, .. } = 拘束.静止摩擦を一回射影する(&参加者)
            {
                予測 = 予測.補正を適用する(&補正a);
            }
        }
        予測
    }
}
