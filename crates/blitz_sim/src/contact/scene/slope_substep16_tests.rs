//! 反証(4)(c)と(4)(f)。判断19の2026-09-12の実装の細目。Issue #59の完了条件)。
//! 担当するのは2つである。本番の当て方(δ の内側の点の行を積まず右辺を −C_t)で、細分数16・静止摩擦係数0.6・
//! 正接0.55の箱が鉛直軸まわりの回し0度・30度・45度の3方向とも600刻みで保持すること。旧の当て方(全部の点の行を積み
//! 右辺を −(C_t − δ))を対照として同じ場面へ当てると、回し0度で滑走すること(段階A2の計測(い)が測った185メートル)。
//! 反証を「新形で通り、旧形で落ちる」の対にするのは、この検査が通る理由が右辺の δ の追い出しであることを固定するためである。
//! 判断19が n = 16 を箱の塔の実測だけで確定していたため、接線の荷重を持つ場面での検収がこの試験である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use std::f32::consts::PI;

use super::super::friction_coefficient::摩擦係数;
use super::super::normal_tangential_system::{
    接線の行への許容差の当て方, 解けたと見なす許容差の倍率, 試験の許容差の当て方
};
use super::slope_fixture::坂の場面を指定で組む;
use super::slope_geometry::坂の場面の条件;
use super::slope_holding::坂の箱の保持と滑走;
use super::slope_scene_spec::{坂の場面の一刻みの細分数, 坂の場面の組み立ての指定};
use super::static_friction_method::場面の静止摩擦の解き方;

const 保持を見る刻み数: usize = 600;
const 三方向の回し: &[f32] = &[0.0, PI / 6.0, PI / 4.0];
const 完了条件の傾きの正接: f32 = 0.55;

fn 傾きの条件(鉛直軸まわりの回し: f32) -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接: 完了条件の傾きの正接,
        鉛直軸まわりの回し,
        静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    }
}

// 細分数16の坂の場面を指定の当て方で600刻み進めた分類。
fn 細分十六本で分類する(条件: &坂の場面の条件, 当て方: 試験の許容差の当て方) -> 坂の箱の保持と滑走 {
    let 指定 = 坂の場面の組み立ての指定 {
        一刻みの細分数: 坂の場面の一刻みの細分数::十六本,
        試験の許容差の当て方: 当て方,
        ..坂の場面の組み立ての指定::既定()
    };
    let mut 場面 = 坂の場面を指定で組む(条件, &指定);
    let 初めの重心 = 場面.箱の配置.重心の位置();
    場面.細分を進める(保持を見る刻み数 * 坂の場面の一刻みの細分数::十六本.本数());
    坂の箱の保持と滑走::場面から決める(&場面, 初めの重心, 条件)
}

#[test]
fn 本番の細分数十六で正接零点五五の箱が三方向とも保持する() {
    for &回し in 三方向の回し {
        assert_eq!(
            細分十六本で分類する(&傾きの条件(回し), 試験の許容差の当て方::本番と同じ当て方()),
            坂の箱の保持と滑走::保持,
            "細分数16・回し{回し}・正接{完了条件の傾きの正接}の箱が保持しない"
        );
    }
}

#[test]
fn 対照の旧の形では細分数十六で正接零点五五の箱が滑走する() {
    let 旧の形 = 試験の許容差の当て方::倍率と行への当て方から生成する(
        解けたと見なす許容差の倍率::既定で生成する(),
        接線の行への許容差の当て方::右辺へ受理の倍率を掛けて残す,
    );
    assert_eq!(
        細分十六本で分類する(&傾きの条件(0.0), 旧の形),
        坂の箱の保持と滑走::滑走,
        "右辺に δ を残す旧の形が細分数16で正接{完了条件の傾きの正接}の箱を保持した。対照が反証として働いていない"
    );
}
