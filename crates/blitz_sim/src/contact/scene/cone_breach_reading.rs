//! 円錐を超えて滑走へ移った接触点集合1つについて、判定がその瞬間に読んだ量(Issue #103の段階A6の追補)。
//! 読むのは、法線の乗数の合計 Σλ_n と、接線の乗数の合力の大きさ ‖Σλ_t‖ と、判定が比べた円錐の半径である。
//! 解けなかった連立の読み取り(`unsolved_system_reading`)から分けているのは、あちらが粘着の候補が定まらなかった
//! 集合の読み取りであり、こちらが定まった解が円錐の外に居た集合の読み取りだからである。この2つは解法の別の枝である。
//! これが要るのは、細分の終わりに反復ごとに読む量が、滑走へ移った後の値(合力が零)になっているためである。
//! 滑走の瞬間に比がいくつまで跳んだかは、判定が読んだこの3つでしか分からない。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::contact_property::接触物性;
use super::super::static_friction::接触点集合の静止摩擦の仮の集計;

/// 円錐を超えた接触点集合1つの読み取り。
pub(super) struct 円錐を超えた接触点集合の読み取り {
    法線の乗数の合計: f64,
    接線の合力の大きさ: f64,
    円錐の半径: f64,
}

impl 円錐を超えた接触点集合の読み取り {
    /// 判定が読んだ集計と接触物性から組む。
    pub(super) fn 集計と接触物性から読む(集計: &接触点集合の静止摩擦の仮の集計, 接触物性: 接触物性) -> Self {
        Self {
            法線の乗数の合計: f64::from(集計.法線の乗数の合計().値()),
            接線の合力の大きさ: f64::from(集計.接線の乗数の合計().大きさ().値()),
            円錐の半径: f64::from(接触物性.静止摩擦の円錐の半径を求める(集計.法線の乗数の合計()).値()),
        }
    }

    /// 表へ綴る形。比は ‖Σλ_t‖ ÷ Σλ_n であり、超過の倍率は ‖Σλ_t‖ ÷ 円錐の半径である。
    pub(super) fn 綴り(&self) -> String {
        let 比 = if self.法線の乗数の合計 > 0.0 {
            self.接線の合力の大きさ / self.法線の乗数の合計
        } else {
            0.0
        };
        let 超過の倍率 = if self.円錐の半径 > 0.0 {
            self.接線の合力の大きさ / self.円錐の半径
        } else {
            0.0
        };
        format!(
            "円錐を超えた Σλ_n={:.6e} ‖Σλ_t‖={:.6e} 比={比:.6} 円錐の半径={:.6e} 超過の倍率={超過の倍率:.6}",
            self.法線の乗数の合計, self.接線の合力の大きさ, self.円錐の半径
        )
    }
}
