//! 粘着の候補を捨てた接触点集合の後始末(判断13の試験専用の実装)。担当するのは、混合の連立の解を捨て、同じ開始の
//! 配置から法線だけの連立を解き直し、その法線の解だけを確定して集合を滑走中へ移すことである。
//! 解く工程(`substep_sticking_candidate`)から分けているのは、こちらが捨てた後の別の局面だからである。
//! 円錐を超えた細分で錨を置き直す先は、法線だけの連立を解き終えた配置の接触点である。混合の連立を解く前の配置へ
//! 置くと、次の細分がその遅れと自分の滑りを合わせて戻すことになり、一度滑り出した集合が二度と保持へ戻れない。
//! 一度円錐を超えた集合をこの細分の後の反復で判定し直さないのは、置き直した錨からの新しい接線変位が円錐の内側へ
//! 入り、位置の静止摩擦と速度の動摩擦が同じ細分で二重に効くためである(印は`滑走中か`が持つ)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::super::static_friction::接触点集合の仮の乗数の集まり;
use super::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_xpbd::{予測の状態, 姿勢自由度の参加者};

impl 一つの箱と静的な直方体の場面 {
    /// 円錐を超えた粘着の候補を全部捨て、同じ開始の配置から法線だけの連立を解いて集合を滑走中へ移す。
    pub(super) fn 粘着の候補を捨てて滑走中にする(
        &self,
        接触点集合: &mut [剛体と静的世界の接触拘束],
        射影の前の予測: 予測の状態,
        仮の乗数: &接触点集合の仮の乗数の集まり,
    ) -> 予測の状態 {
        let 法線を解いた予測 = self.接触点集合の非貫通を同時に解く(接触点集合, 射影の前の予測);
        let 参加者 = 姿勢自由度の参加者::動的(*法線を解いた予測.配置(), &self.箱の質量特性);
        self.接触点集合を滑走中にする(接触点集合, &参加者, 仮の乗数);
        法線を解いた予測
    }

    /// 滑走中と印し、錨を渡した配置の接触点へ置き直す。法線反力の無い点の接線の乗数だけは零へ確定する。
    pub(super) fn 接触点集合を滑走中にする(
        &self,
        接触点集合: &mut [剛体と静的世界の接触拘束],
        参加者: &姿勢自由度の参加者,
        仮の乗数: &接触点集合の仮の乗数の集まり,
    ) {
        for (添字, 拘束) in 接触点集合.iter_mut().enumerate() {
            拘束.接触点集合が滑走中になったと印す(参加者);
            if 仮の乗数.一点の仮の接線の乗数(添字).集合が円錐を超えても解放するか() {
                拘束.静止摩擦の接線の乗数を零へ解放する();
            }
        }
    }
}
