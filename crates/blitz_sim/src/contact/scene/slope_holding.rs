//! 坂の場面の走行の結果を、保持と滑走の2値へ写す読み出し(判断13の検収)。保持と決めるのは、坂に沿った変位が保持の
//! 上限(1ミリメートル)の内側であることと、最後の細分に滑走中と印された接触点が無いことの両方である。変位だけで
//! 決めないのは、円錐を超えた直後の細分ではまだ変位が小さく、滑走へ移った事実を見落とすためである。
//! 分類の型が場面から自分を組み立てる形にし、場面の型へメソッドを足さないのは、場面の型が既に41のメソッドを
//! 持ち、読む口をこれ以上増やさないためである。
//! 受理の倍率を振って分類が変わらないことを固定する検査(`slope_tolerance_scale_tests` ほか)がこの口を読む。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_math::{ワールド, 二段の位置};

use super::slope_geometry::坂の場面の条件;
use super::substep_harness::一つの箱と静的な直方体の場面;

// 受入条件が定める保持の上限。`slope_tests` が固定する値と同じである。
const 保持を要求する変位の上限: f32 = 1.0e-3;

/// 坂の箱の保持と滑走の分類。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 坂の箱の保持と滑走 {
    保持,
    滑走,
}

impl 坂の箱の保持と滑走 {
    /// 走らせた後の場面と初めの重心から決める。変位が上限の内側で、かつ最後の細分に滑走中の接触点が無いときだけ保持である。
    pub(super) fn 場面から決める(
        場面: &一つの箱と静的な直方体の場面, 初めの重心: 二段の位置<ワールド>, 条件: &坂の場面の条件
    ) -> Self {
        let 変位の内側 = 場面.坂に沿った変位(初めの重心, 条件).abs() <= 保持を要求する変位の上限;
        if 変位の内側 && 場面.直前の細分の観測.滑走中の接触点の数 == 0 {
            Self::保持
        } else {
            Self::滑走
        }
    }
}
