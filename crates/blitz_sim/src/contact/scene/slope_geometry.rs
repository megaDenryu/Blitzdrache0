//! 坂の場面の幾何(判断13・判断14の検収)。傾きの正接と鉛直軸まわりの回しから、坂の姿勢・面の法線・下り向き・
//! 滑り落ちる加速度を求める。場面の組み立て(`slope_fixture`)から分けているのは、こちらが場面の状態を持たない
//! 三角関数だけの計算であり、試験が解析値を作るのにも使うためである。
//!   面の法線 R(q) ŷ = (sinψ sinθ, cosθ, cosψ sinθ)、下り向き (cosθ sinψ, −sinθ, cosθ cosψ)
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{ワールド, 方向};

use super::super::friction_coefficient::摩擦係数;
use super::scene_geometry::{世界の変位, 姿勢を軸の回転から作る};
use crate::rigid_body::姿勢;

pub(super) const 重力の大きさ: f32 = 9.81;

// 坂の場面の条件。傾きは正接で与える(静止摩擦係数と直接比べるため)。
pub(super) struct 坂の場面の条件 {
    pub 傾きの正接: f32,
    pub 鉛直軸まわりの回し: f32,
    pub 静止摩擦係数: 摩擦係数,
    pub 動摩擦係数: 摩擦係数,
    pub 下り向きの初速: f32,
    pub 静止摩擦の位置拘束を外すか: bool,
}

impl 坂の場面の条件 {
    // 坂の面の法線。箱を面へ密着させる位置もこの向きで測る。
    pub(super) fn 坂の面の法線(&self) -> 方向<ワールド> {
        let (正弦, 余弦) = 傾きの正弦と余弦(self.傾きの正接);
        let (回しの正弦, 回しの余弦) = self.鉛直軸まわりの回し.sin_cos();
        方向::生成する(回しの正弦 * 正弦, 余弦, 回しの余弦 * 正弦).unwrap()
    }

    // 坂の面を最も急に下る向き。重力の面内成分の向きである。
    pub(super) fn 坂の下り向き(&self) -> 方向<ワールド> {
        let (正弦, 余弦) = 傾きの正弦と余弦(self.傾きの正接);
        let (回しの正弦, 回しの余弦) = self.鉛直軸まわりの回し.sin_cos();
        方向::生成する(余弦 * 回しの正弦, -正弦, 余弦 * 回しの余弦).unwrap()
    }

    // 鉛直軸まわりの回し ψ と x軸まわりの傾き θ を合成した姿勢 q = q_ψ ⊗ q_θ。坂と箱がこの姿勢を共有する。
    pub(super) fn 坂の姿勢(&self) -> 姿勢 {
        let 傾き = 姿勢を軸の回転から作る(世界の変位(1.0, 0.0, 0.0), self.傾きの正接.atan());
        let 回し = 姿勢を軸の回転から作る(世界の変位(0.0, 1.0, 0.0), self.鉛直軸まわりの回し);
        姿勢::回転から生成する(傾き.回転().続けて回す(&世界から世界への回転として読む(&回し)))
    }
}

// 傾きの正接に対する、坂を滑り落ちる加速度 g(sinθ − μ_d cosθ)。
pub(super) fn 滑走の加速度(傾きの正接: f32, 動摩擦係数: f32) -> f32 {
    let (正弦, 余弦) = 傾きの正弦と余弦(傾きの正接);
    重力の大きさ * (正弦 - 動摩擦係数 * 余弦)
}

fn 傾きの正弦と余弦(傾きの正接: f32) -> (f32, f32) {
    let 余弦 = 1.0 / (1.0 + 傾きの正接 * 傾きの正接).sqrt();
    (傾きの正接 * 余弦, 余弦)
}

// 回しの姿勢をワールドからワールドへの回転として読む。傾きの姿勢へ左から掛けるための綴りである。
fn 世界から世界への回転として読む(回し: &姿勢) -> blitz_math::クォータニオン<ワールド, ワールド> {
    let [x, y, z, w] = 回し.境界用xyzw配列();
    blitz_math::クォータニオン::生成する(x, y, z, w).unwrap()
}
