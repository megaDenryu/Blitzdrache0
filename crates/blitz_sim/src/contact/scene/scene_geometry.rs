//! 場面の材料を世界座標で組む道具(判断19の細分の工程の試験専用の実装)。担当するのは、配置と半分の長さから
//! 衝突数学層の直方体を組むことと、成分から世界の位置と変位を作ることと、軸と角から姿勢を作ることと、
//! 一様な立方体の質量特性と単一の材質の混合則を作ることである。場面の状態を持たない純粋な組み立てだけを置く。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_collision::shape::{任意姿勢の直方体, 直方体の軸ごとの半分の長さ};
use blitz_math::{キログラム, クォータニオン, メートル, ローカル, ワールド, 位置, 変位};

use super::super::material_id::材質の識別子;
use super::super::mixing_rule::混合則;
use super::super::mixing_rule_builder::混合則の組み立て;
use super::super::surface_property::表面物性;
use crate::rigid_body::{姿勢, 質量特性, 配置};

pub(super) const 場面の材質: u32 = 0;

pub(super) fn 一様な立方体の質量特性(質量: f32, 半分の長さ: f32) -> 質量特性 {
    let 一辺 = メートル::生成する(2.0 * 半分の長さ);
    質量特性::一様な箱(キログラム::生成する(質量).unwrap(), 一辺, 一辺, 一辺).unwrap()
}

/// 配置の重心をそのまま形の中心に置いた立方体。初版の共有の座標系はワールドである。
pub(super) fn 直方体を組む(配置: &配置, 半分の長さ: f32) -> 任意姿勢の直方体 {
    let 中心: 位置<ローカル> = 位置::生成する(配置.重心の位置().x(), 配置.重心の位置().y(), 配置.重心の位置().z());
    let [x, y, z, w] = 配置.姿勢().境界用xyzw配列();
    任意姿勢の直方体::生成する(
        中心,
        クォータニオン::生成する(x, y, z, w).unwrap(),
        直方体の軸ごとの半分の長さ::生成する([メートル::生成する(半分の長さ); 3]).unwrap(),
    )
    .unwrap()
}

pub(super) fn 世界の位置(x: f32, y: f32, z: f32) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

pub(super) fn 世界の変位(x: f32, y: f32, z: f32) -> 変位<ワールド> {
    変位::成分から生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

/// 軸まわりに指定の角だけ回した姿勢。四元数の成分は (軸 sin(θ/2), cos(θ/2)) である。
pub(super) fn 姿勢を軸の回転から作る(軸: 変位<ワールド>, 角: f32) -> 姿勢 {
    let 単位軸 = 軸.単位方向().unwrap();
    let (半角の正弦, 半角の余弦) = (0.5 * 角).sin_cos();
    姿勢::生成する(単位軸.x() * 半角の正弦, 単位軸.y() * 半角の正弦, 単位軸.z() * 半角の正弦, 半角の余弦).unwrap()
}

pub(super) fn 単一の材質の混合則(表面物性: 表面物性) -> 混合則 {
    let mut 組み立て = 混合則の組み立て::生成する();
    組み立て.表面物性を登録する(材質の識別子::生成する(場面の材質), 表面物性).unwrap();
    組み立て.組み立てる().unwrap()
}
