//! 坂の上の箱で、面と面の4点の法線の乗数の合計が真の法線力積へ寄ることの検査(判断12)。
//! 担当するのは2つである。合計と解析値 m g cosθ h² の差が、位置の反復回数2・4・8のどれでも3パーセント以内に
//! 収まること、そして反復回数を増やしても細分の末の最大の食い込みが増えないことである。
//! 反復回数16と32はこの検査に入れない。差が3.80パーセントと6.41パーセントへ広がり、3パーセントに収まらないためである
//! (実測は`_doc/計測/剛体の接触の摩擦と反発_2026-09-03.md`)。
//! 点を順に配置へ適用する解き方では、点Aの補正が点Bを離し次の巡回でAの乗数を解放する往復が起き、反復回数を
//! 増やすほど合計が真の法線力積から離れた(反復8で21パーセント下回った。実測は
//! `_doc/計測/剛体の接触の摩擦と反発_2026-09-03.md`)。接触点集合を1つの連立として解くとこの往復が消える。
//! 差が反復回数に対して単調に減ることは拘束の不変条件ではない。有限回転で配置を毎反復に線形化し直し、静止摩擦も
//! 間に適用するためである。合否は絶対の誤差と、食い込みが増えないことで判定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

#![allow(clippy::unwrap_used)]

use super::super::friction_coefficient::摩擦係数;
use super::slope_fixture::{一刻みの細分数, 坂の場面を位置の反復回数で組む};
use super::slope_geometry::{坂の場面の条件, 重力の大きさ};
use super::static_friction_method::場面の静止摩擦の解き方;

const 測る傾きの正接: f32 = 0.9; // 滑走中の坂。正本の判断12の実装の細目が同じ条件で記録している
const 落ち着くまでの刻み数: usize = 8;
const 平均を取る細分数: usize = 480;
const 平均を取る細分数の実数: f32 = 480.0; // 平均を取る細分数と同じ値。整数から実数への縮小変換を避けるために別に置く
const 許す相対誤差: f32 = 0.03; // 逐次に解く実装は同じ条件で反復8で0.216であった
const 振る位置の反復回数: [u32; 3] = [2, 4, 8];
const 食い込みが増えたと見なす比: f32 = 1.05; // 丸めで末尾の桁が動くため、増えたと見なす下限を5パーセント置く

fn 測る条件() -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接: 測る傾きの正接,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    }
}

// 細分1本あたりの法線力積の解析値 m g cosθ h²。質量1キログラム、細分の刻み幅は1/480秒である。
fn 法線の乗数の合計の解析値() -> f32 {
    let 余弦 = 1.0 / (1.0 + 測る傾きの正接 * 測る傾きの正接).sqrt();
    let 刻み幅 = 1.0 / 480.0;
    重力の大きさ * 余弦 * 刻み幅 * 刻み幅
}

// 法線の乗数の合計の平均と、その間に見た最も深い食い込み。
fn 法線の乗数の合計の平均と最大の食い込み(位置の反復回数: u32) -> (f32, f32) {
    let mut 場面 = 坂の場面を位置の反復回数で組む(&測る条件(), 位置の反復回数);
    場面.細分を進める(落ち着くまでの刻み数 * 一刻みの細分数);
    let mut 和 = 0.0;
    let mut 最大の食い込み: f32 = 0.0;
    for _ in 0..平均を取る細分数 {
        場面.一細分進める();
        和 += 場面.直前の細分の観測.法線の乗数の合計.値();
        最大の食い込み = 最大の食い込み.max(場面.直前の細分の観測.最大の食い込み.値());
    }
    (和 / 平均を取る細分数の実数, 最大の食い込み)
}

#[test]
fn 法線の乗数の合計は位置の反復回数を増やしても真の法線力積から離れない() {
    let 解析値 = 法線の乗数の合計の解析値();
    let mut 前の食い込み = f32::MAX;
    for 反復回数 in 振る位置の反復回数 {
        let (平均, 最大の食い込み) = 法線の乗数の合計の平均と最大の食い込み(反復回数);
        let 相対誤差 = (平均 - 解析値).abs() / 解析値;
        assert!(
            相対誤差 <= 許す相対誤差,
            "反復回数{反復回数}の法線の乗数の合計{平均}が解析値{解析値}と{相対誤差}ずれた"
        );
        assert!(
            最大の食い込み <= 前の食い込み * 食い込みが増えたと見なす比,
            "反復回数{反復回数}で最大の食い込み{最大の食い込み}が前の反復回数の{前の食い込み}より増えた"
        );
        前の食い込み = 最大の食い込み;
    }
}
