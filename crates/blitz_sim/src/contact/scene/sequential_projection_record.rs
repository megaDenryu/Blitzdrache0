//! 接線を接触点ごとに順に射影する反証の経路と、接触点集合の接線を同時に解く本番の経路を、正接0.50の坂で細分ごとに
//! 並べる計器(判断13。Issue #59の第3段階)。合否は判定しない。
//! 綴るのは細分ごとの、接線の乗数の合力の大きさ・法線の乗数の合計・その比・滑走中の接触点の数・坂に沿った変位であり、
//! 末尾に600刻みの変位を並べる。順の射影が保持の上限に留まる理由(接線の乗数が積み増されなくなったのか、円錐を
//! 超える手前で止まるのか)を読むための表である。
//! 実行は `cargo test -p blitz_sim --release 順の射影と同時解の接線の乗数を細分ごとに並べて記録する -- --ignored --nocapture` である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::super::friction_coefficient::摩擦係数;
use super::slope_fixture::{一刻みの細分数, 坂の場面を組む};
use super::slope_geometry::坂の場面の条件;
use super::static_friction_method::場面の静止摩擦の解き方;

const 傾きの正接: f32 = 0.50;
const 綴る細分の本数: usize = 64;
const 変位を測る刻み数: usize = 600;

fn 条件(解き方: 場面の静止摩擦の解き方) -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の解き方: 解き方,
    }
}

fn 一つの経路を綴る(解き方: 場面の静止摩擦の解き方) {
    let 条件 = 条件(解き方);
    let mut 場面 = 坂の場面を組む(&条件);
    let 初めの重心 = 場面.箱の配置.重心の位置();
    println!("[{解き方:?}] 細分 | ‖Σλ_t‖ | Σλ_n | 比 | 滑走中の点 | 変位");
    for 番号 in 0..綴る細分の本数 {
        場面.一細分進める();
        let 観測 = 場面.直前の細分の観測;
        let 接線 = 観測.接線の乗数の合力の大きさ.値();
        let 法線 = 観測.法線の乗数の合計.値();
        println!(
            "  {番号} | {接線:.6e} | {法線:.6e} | {:.6} | {} | {:.6e}",
            接線 / 法線,
            観測.滑走中の接触点の数,
            場面.坂に沿った変位(初めの重心, &条件)
        );
    }
    場面.細分を進める(変位を測る刻み数 * 一刻みの細分数 - 綴る細分の本数);
    println!(
        "[{解き方:?}] {変位を測る刻み数}刻みの坂に沿った変位={:.6e}",
        場面.坂に沿った変位(初めの重心, &条件)
    );
}

