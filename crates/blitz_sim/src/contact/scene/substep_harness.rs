//! 1つの動的な直方体と1つの静的な直方体だけの場面と、その設定(判断19の細分の工程の試験専用の実装)。
//! この型が持つのは場面の状態と、判断19の工程を回すのに要る部品(混合則・予測器・速度段階・履歴)である。
//! 細分1本を進める工程そのものは`substep_step`が持つ。生成と読み出しは場面ごとに1度、工程は細分ごとに呼ばれるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_collision::shape::任意姿勢の直方体;
use blitz_math::{メートル, 角速度};

use super::super::contact_thresholds::反発を抑制する法線相対速度の閾値;
use super::super::history::剛体と静的世界の接触の履歴;
use super::super::material_id::材質の識別子;
use super::super::minimum_thickness::形の最小の厚み;
use super::super::mixing_rule::混合則;
use super::super::normal_tangential_system::解けたと見なす許容差の倍率;
use super::super::solver_quality::接触を解く品質の設定;
use super::super::static_world_partner::静的世界の接触相手;
use super::super::static_world_partner_id::静的世界の接触相手の識別子;
use super::super::velocity_stage::接触の速度段階;
use super::scene_geometry::{一様な立方体の質量特性, 単一の材質の混合則, 場面の材質, 直方体を組む};
use super::scene_settings::{場面の設定, 細分の観測};
use super::static_friction_method::場面の静止摩擦の解き方;
use crate::rigid_body::{剛体の台帳, 剛体の識別子, 質量特性, 運動状態, 運動種別, 配置};
use crate::rigid_xpbd::{ジャイロ項の扱い, 細分の予測器};
use crate::xpbd::刻み幅;

const 静的世界の番号: u32 = 1;
const 見込みの接触点の数: usize = 8;

pub(super) struct 一つの箱と静的な直方体の場面 {
    pub(super) 箱の識別子: 剛体の識別子,
    pub(super) 箱の配置: 配置,
    pub(super) 箱の運動状態: 運動状態,
    pub(super) 箱の質量特性: 質量特性,
    pub(super) 箱の半分の長さ: メートル,
    pub(super) 静的な直方体: 任意姿勢の直方体,
    pub(super) 静的世界の接触相手: 静的世界の接触相手,
    pub(super) 混合則: 混合則,
    pub(super) 予測器: 細分の予測器,
    pub(super) 速度段階: 接触の速度段階,
    pub(super) 刻み幅: 刻み幅,
    pub(super) 解く品質: 接触を解く品質の設定,
    pub(super) 履歴: 剛体と静的世界の接触の履歴,
    pub(super) 直前の細分の観測: 細分の観測,
    pub(super) 静止摩擦の解き方: 場面の静止摩擦の解き方,
    pub(super) 解けたと見なす許容差の倍率: 解けたと見なす許容差の倍率,
    pub(super) 粘着の候補が解けなかった接触点集合の延べ数: usize, // 場面を組んでからの累計。検査が零を固定する
}

impl 一つの箱と静的な直方体の場面 {
    pub(super) fn 生成する(設定: &場面の設定) -> Self {
        let mut 台帳 = 剛体の台帳::空();
        let 質量特性 = 一様な立方体の質量特性(設定.箱の質量, 設定.箱の半分の長さ);
        let 箱の識別子 = 台帳
            .登録する(
                設定.箱の配置,
                質量特性,
                運動種別::動的で始める(運動状態::生成する(設定.箱の初速, 角速度::零())),
            )
            .unwrap();
        Self {
            箱の識別子,
            箱の配置: 設定.箱の配置,
            箱の運動状態: 運動状態::生成する(設定.箱の初速, 角速度::零()),
            箱の質量特性: 質量特性,
            箱の半分の長さ: 設定.箱の半分の長さ,
            静的な直方体: 直方体を組む(&設定.静的な直方体の配置, 設定.静的な直方体の半分の長さ),
            静的世界の接触相手: 静的世界の接触相手::生成する(
                静的世界の接触相手の識別子::生成する(静的世界の番号),
                材質の識別子::生成する(場面の材質),
                形の最小の厚み::生成する(設定.静的な直方体の半分の長さ * 2.0).unwrap(),
            ),
            混合則: 単一の材質の混合則(設定.表面物性),
            予測器: 細分の予測器::生成する(設定.細分の刻み幅, 設定.重力, ジャイロ項の扱い::陰的に一段解く),
            速度段階: 接触の速度段階::生成する(設定.細分の刻み幅, 反発を抑制する法線相対速度の閾値(設定.重力, 設定.細分の刻み幅)),
            刻み幅: 設定.細分の刻み幅,
            解く品質: 設定.解く品質,
            履歴: 剛体と静的世界の接触の履歴::見込みの接触点の数で生成する(見込みの接触点の数),
            直前の細分の観測: 細分の観測::default(),
            静止摩擦の解き方: 設定.静止摩擦の解き方,
            解けたと見なす許容差の倍率: 設定.解けたと見なす許容差の倍率,
            粘着の候補が解けなかった接触点集合の延べ数: 0,
        }
    }

    // 細分を指定の本数だけ進める。基本刻み1本は細分数ぶんの呼び出しである。
    pub(super) fn 細分を進める(&mut self, 本数: usize) {
        for _ in 0..本数 {
            self.一細分進める();
        }
    }

    // 箱の重心から見た指定の高さの向きの隙間。落下の試験が床からの隙間を測るために読む。
    pub(super) fn 箱の重心の高さ(&self) -> メートル {
        self.箱の配置.重心の位置().y()
    }
}
