//! 細分1本の観測を組む工程(判断19の細分の工程の試験専用の実装)。担当するのは、反復を終えたバッチと配置から
//! 接触点の数・開始した接触点の数・滑走中の接触点の数・法線の乗数の合計・最大の食い込み・接線の乗数の合力の
//! 大きさの6つを読み出すことである。
//! 細分1本の工程(`substep_step`)から分けているのは、あちらが状態を進める局面であり、こちらが進め終えた状態を
//! 読むだけの局面だからである。この工程はどの状態も書き換えない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」

#![cfg(test)]

use blitz_math::{メートル, ワールド, 変位, 速度};

use super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::super::contact_batches::接触拘束の二つのバッチ;
use super::super::static_friction::接線のラグランジュ乗数;
use super::scene_settings::細分の観測;
use super::substep_harness::一つの箱と静的な直方体の場面;
use super::substep_residual_observation::細分の残差の観測;
use crate::rigid_xpbd::予測の状態;
use crate::xpbd::ラグランジュ乗数;

impl 一つの箱と静的な直方体の場面 {
    pub(super) fn 細分の観測を作る(
        &self,
        バッチ: &接触拘束の二つのバッチ,
        予測: &予測の状態,
        開始した接触点の数: usize,
        仮の補正を引く前の並進速度: 速度<ワールド>,
    ) -> 細分の観測 {
        let 拘束一覧 = バッチ.剛体と静的世界の接触拘束();
        細分の観測 {
            接触点の数: 拘束一覧.len(),
            開始した接触点の数,
            滑走中の接触点の数: 拘束一覧.iter().filter(|拘束| 拘束.静止摩擦の解の状態().滑走中か()).count(),
            法線の乗数の合計: 拘束一覧
                .iter()
                .fold(ラグランジュ乗数::零(), |合計, 拘束| 合計 + 拘束.法線のラグランジュ乗数()),
            最大の食い込み: self.反復を終えた最大の食い込み(バッチ, 予測),
            残差の観測: 残差の観測を作る(拘束一覧, 仮の補正を引く前の並進速度),
            接線の乗数の合力の大きさ: 拘束一覧
                .iter()
                .fold(接線のラグランジュ乗数::零(), |合計, 拘束| {
                    合計 + 拘束.静止摩擦の解の状態().接線のラグランジュ乗数()
                })
                .大きさ(),
        }
    }
}

// この細分に残差の変化を持った点の変化の一覧。計器がその数と最大の長さを読む。
fn 残差の変化の一覧(拘束一覧: &[剛体と静的世界の接触拘束]) -> impl Iterator<Item = 変位<ワールド>> + '_ {
    拘束一覧.iter().filter_map(|拘束| 拘束.残差の持ち越しを読む().細分のあいだの残差の変化())
}

// 判断24の契約がこの細分で何をしたかの観測。長さは点ごとの最大を採る。
fn 残差の観測を作る(
    拘束一覧: &[剛体と静的世界の接触拘束], 仮の補正を引く前の並進速度: 速度<ワールド>
) -> 細分の残差の観測 {
    細分の残差の観測 {
        粘着の候補を確定した点の数: 拘束一覧.iter().filter(|拘束| 拘束.静止摩擦の解の状態().粘着の候補を確定したか()).count(),
        残差の変化が在る点の数: 残差の変化の一覧(拘束一覧).count(),
        残差の変化の最大の長さ: メートル::生成する(残差の変化の一覧(拘束一覧).map(|変化| 変化.長さ().値()).fold(0.0, f32::max)),
        細分の終わりの残差の最大の長さ: メートル::生成する(
            拘束一覧
                .iter()
                .filter_map(|拘束| 拘束.残差の持ち越しを読む().履歴へ書き戻す残差().測った変位())
                .map(|残差| 残差.長さ().値())
                .fold(0.0, f32::max),
        ),
        仮の補正を引く前の並進速度,
    }
}
