//! 滑走中の坂の箱で、細分ごとの法線の乗数の合計 Σλ_n が解析の法線力積 m g cosθ h² とどれだけ違うかを綴る計器
//! (判断12・判断14。PR #97 の受理阻害2の診断)。減速度の相対誤差が動摩擦係数0.55でだけ1パーセントを超えた原因を、
//! 法線の側(Σλ_n の比)と接線の側(‖Σλ_t‖ と Σλ_n の比、滑走中の点の数)に切り分けるためにある。合否は判定しない。
//! 綴るのは、動摩擦係数・残差の分離・位置の反復回数の組ごとに、減速度を測る窓(細分60から300)の Σλ_n の比の平均・最小・最大、
//! ‖Σλ_t‖ ÷ Σλ_n の平均、滑走中の点の数の平均、減速度の相対誤差である。窓と条件は `sliding_deceleration_tests` と同じにする。
//! 位置の反復回数を2(既定)と8で振るのは、比の解析値からの離れが反復の不足によるものかを見るためである。
//! 実行は `cargo test -p blitz_sim --release 滑走中の法線の乗数の合計の比を係数と残差の分離ごとに記録する -- --ignored --nocapture` である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::super::friction_coefficient::摩擦係数;
use super::residual_separation::場面の残差の分離;
use super::slope_fixture::坂の場面を位置の反復回数で組む;
use super::slope_geometry::{坂の場面の条件, 滑走の加速度, 重力の大きさ};
use super::static_friction_method::場面の静止摩擦の解き方;
use super::substep_harness::一つの箱と静的な直方体の場面;

const 滑る傾きの正接: f32 = 0.9;
const 静止摩擦係数の値: f32 = 0.6;
const 下り向きの初速: f32 = 1.0;
const 測り始めるまでの細分数: usize = 60;
const 測る細分数: usize = 240;
const 測る細分数の実数: f32 = 240.0; // 測る細分数と同じ値。整数から実数への縮小変換を避けるために別に置く
const 測る秒数: f32 = 0.5;
const 振る動摩擦係数: [f32; 4] = [0.1, 0.2, 0.4, 0.55];
const 既定の位置の反復回数: u32 = 2;
const 増やした位置の反復回数: u32 = 8;

// 細分1本あたりの法線力積の解析値 m g cosθ h²。質量1キログラム、細分の刻み幅は1/480秒である。
fn 法線力積の解析値() -> f32 {
    let 余弦 = 1.0 / (1.0 + 滑る傾きの正接 * 滑る傾きの正接).sqrt();
    let 刻み幅 = 1.0 / 480.0;
    重力の大きさ * 余弦 * 刻み幅 * 刻み幅
}

struct 窓の集計 {
    比の和: f32,
    比の最小: f32,
    比の最大: f32,
    接線と法線の比の和: f32,
    滑走中の点の数の和: f32,
    減速度の相対誤差: f32,
}

fn 場面を測る(場面: &mut 一つの箱と静的な直方体の場面, 条件: &坂の場面の条件) -> 窓の集計 {
    場面.細分を進める(測り始めるまでの細分数);
    let 初めの速さ = 場面.下り向きの速さ(条件);
    let 解析値 = 法線力積の解析値();
    let mut 集計 = 窓の集計 {
        比の和: 0.0,
        比の最小: f32::MAX,
        比の最大: f32::MIN,
        接線と法線の比の和: 0.0,
        滑走中の点の数の和: 0.0,
        減速度の相対誤差: 0.0,
    };
    for _ in 0..測る細分数 {
        場面.一細分進める();
        let 観測 = 場面.直前の細分の観測;
        let 比 = 観測.法線の乗数の合計.値() / 解析値;
        集計.比の和 += 比;
        集計.比の最小 = 集計.比の最小.min(比);
        集計.比の最大 = 集計.比の最大.max(比);
        集計.接線と法線の比の和 += 観測.接線の乗数の合力の大きさ.値() / 観測.法線の乗数の合計.値();
        集計.滑走中の点の数の和 += f32::from(u16::try_from(観測.滑走中の接触点の数).unwrap());
    }
    let 測った加速度 = (場面.下り向きの速さ(条件) - 初めの速さ) / 測る秒数;
    let 解析の加速度 = 滑走の加速度(滑る傾きの正接, 条件.動摩擦係数.値());
    集計.減速度の相対誤差 = (測った加速度 - 解析の加速度).abs() / 解析の加速度;
    集計
}

fn 一つの組を綴る(動摩擦係数の値: f32, 分離: 場面の残差の分離, 位置の反復回数: u32) {
    let 条件 = 坂の場面の条件 {
        傾きの正接: 滑る傾きの正接,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(静止摩擦係数の値).unwrap(),
        動摩擦係数: 摩擦係数::生成する(動摩擦係数の値).unwrap(),
        下り向きの初速,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    };
    let mut 場面 = 坂の場面を位置の反復回数で組む(&条件, 位置の反復回数);
    場面.残差の分離 = 分離;
    let 集計 = 場面を測る(&mut 場面, &条件);
    println!(
        "{動摩擦係数の値} | {分離:?} | {位置の反復回数} | {:.6} | {:.6} | {:.6} | {:.6} | {:.3} | {:.4e}",
        集計.比の和 / 測る細分数の実数,
        集計.比の最小,
        集計.比の最大,
        集計.接線と法線の比の和 / 測る細分数の実数,
        集計.滑走中の点の数の和 / 測る細分数の実数,
        集計.減速度の相対誤差,
    );
}

