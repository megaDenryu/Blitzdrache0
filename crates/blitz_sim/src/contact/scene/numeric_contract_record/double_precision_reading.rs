//! 倍精度の参照計算で粘着の候補を1回解き、比べる量を読み取る工程(Issue #59の数値契約の診断)。
//! 単精度の側と同じ入力(その反復の予測の配置・錨・接触点集合・法線の乗数)から出発し、行の組み立て以降だけを
//! 倍精度で行う。読み取った後の形は単精度の側と同じ型である。
//! 工程を場面のメソッドにしているのは、質量特性を場面が持ち、参照計算がそれを要るためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::super::super::normal_tangential_system::{倍精度の円錐の判定, 倍精度の参照の結末};
use super::super::substep_harness::一つの箱と静的な直方体の場面;
use super::candidate_reading::粘着の候補の読み取り;
use crate::rigid_body::配置;

impl 一つの箱と静的な直方体の場面 {
    /// 倍精度の参照計算で接触点集合1つの粘着の候補を解き、比べる量を読み取る。状態は書き換えない。
    pub(super) fn 倍精度で粘着の候補を読む(
        &self,
        接触点集合: &[剛体と静的世界の接触拘束],
        配置: &配置,
    ) -> 粘着の候補の読み取り {
        let 結末 = 倍精度の参照の結末::単精度の接触点集合から求める(接触点集合, 配置, &self.箱の質量特性);
        let 倍精度の参照の結末::解が定まった(参照の解) = &結末 else {
            return 粘着の候補の読み取り::解けなかった結末から組む(結末.結末の綴り());
        };
        let 判定 = 倍精度の円錐の判定::参照の解と単精度の接触点集合から集計する(参照の解, 接触点集合);
        粘着の候補の読み取り::六つの量から組む(
            "定まった",
            (0..接触点集合.len()).map(|番号| 参照の解.一点の法線の拘束違反(番号)).collect(),
            (0..接触点集合.len()).map(|番号| 参照の解.一点の接線変位の長さ(番号)).collect(),
            判定.法線の乗数の合計(),
            判定.接線の乗数の合力の大きさ(),
            判定.円錐の内側か(),
        )
    }
}
