//! 診断が測る1つの場合を、表の見出しに使う単位から組む3つの口(Issue #59)。
//! 単位は、鉛直軸まわりの回しの度・解けたと見なす許容差の倍率の比・坂の面の法線の向きへ動かす長さのメートルである。
//! 場合の型(`diagnostic_case`)から分けているのは、あちらが場面を組んで走らせる工程を持ち、こちらが「表の欄の
//! 値から場合を作る」ことだけを持つからである。
//! 回しを度で受けるのは、表の見出しが度であり、5つの計器がそれぞれラジアンへの変換を書くと同じ2行が5箇所へ
//! 複製されるためである。変換をこの3つの口の中へ閉じる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_math::{メートル, ラジアン};

use super::super::super::normal_tangential_system::解けたと見なす許容差の倍率;
use super::diagnostic_case::数値契約の診断の一つの場合;

impl 数値契約の診断の一つの場合 {
    pub(super) fn 回しの度と正接から生成する(鉛直軸まわりの回しの度: f32, 傾きの正接: f32) -> Self {
        Self {
            鉛直軸まわりの回し: ラジアン::度から(鉛直軸まわりの回しの度).値(),
            傾きの正接,
            法線の向きへ動かす長さ: メートル::生成する(0.0),
            解けたと見なす許容差の倍率: 解けたと見なす許容差の倍率::既定(),
        }
    }

    /// 解けたと見なす許容差だけを振った場合。世界座標も相対の配置も変えない。
    pub(super) fn 許容差の倍率から生成する(鉛直軸まわりの回し: f32, 傾きの正接: f32, 許容差の比: f32) -> Self {
        Self {
            鉛直軸まわりの回し,
            傾きの正接,
            法線の向きへ動かす長さ: メートル::生成する(0.0),
            解けたと見なす許容差の倍率: 解けたと見なす許容差の倍率::比から生成する(許容差の比),
        }
    }

    /// 坂と箱をまとめて坂の面の法線の向きへ動かした場合。相対の配置は変わらず、座標の表現の刻みだけが変わる。
    pub(super) fn 回しの度と法線の向きへ動かす長さから生成する(
        鉛直軸まわりの回しの度: f32,
        傾きの正接: f32,
        法線の向きへ動かす長さ: メートル,
    ) -> Self {
        Self {
            鉛直軸まわりの回し: ラジアン::度から(鉛直軸まわりの回しの度).値(),
            傾きの正接,
            法線の向きへ動かす長さ,
            解けたと見なす許容差の倍率: 解けたと見なす許容差の倍率::既定(),
        }
    }
}
