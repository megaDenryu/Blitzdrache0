//! 粘着の候補を1回解いた結果から、2つの精度で同じ形に読み取る量(Issue #59の数値契約の診断)。
//! 持つのは、結末の綴り・点ごとの法線の拘束違反 C_n と接線変位 C_t・更新後の Σλ_n・‖Σλ_t‖・円錐の判定である。
//! 単精度と倍精度で同じ型にするのは、比べる相手が同じ形でなければ差を機械で取れないためである。構築の口だけを
//! 精度ごとに分け、読み出しの口は共通にする。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

/// 粘着の候補を1回解いた結果の読み取り。単精度と倍精度のどちらも同じ形で持つ。
pub(super) struct 粘着の候補の読み取り {
    結末の綴り: &'static str,
    点ごとの法線の拘束違反: Vec<f64>,
    点ごとの接線変位: Vec<f64>,
    法線の乗数の合計: f64,
    接線の合力の大きさ: f64,
    円錐の内側か: bool,
}

impl 粘着の候補の読み取り {
    pub(super) fn 六つの量から組む(
        結末の綴り: &'static str,
        点ごとの法線の拘束違反: Vec<f64>,
        点ごとの接線変位: Vec<f64>,
        法線の乗数の合計: f64,
        接線の合力の大きさ: f64,
        円錐の内側か: bool,
    ) -> Self {
        Self {
            結末の綴り,
            点ごとの法線の拘束違反,
            点ごとの接線変位,
            法線の乗数の合計,
            接線の合力の大きさ,
            円錐の内側か,
        }
    }

    pub(super) fn 結末の綴り(&self) -> &'static str {
        self.結末の綴り
    }

    pub(super) fn 点ごとの法線の拘束違反(&self) -> &[f64] {
        &self.点ごとの法線の拘束違反
    }

    pub(super) fn 点ごとの接線変位(&self) -> &[f64] {
        &self.点ごとの接線変位
    }

    pub(super) fn 法線の乗数の合計(&self) -> f64 {
        self.法線の乗数の合計
    }

    pub(super) fn 接線の合力の大きさ(&self) -> f64 {
        self.接線の合力の大きさ
    }

    /// 更新後の合力と法線の乗数の合計の比 ‖Σλ_t‖ ÷ Σλ_n。静止摩擦係数と直に比べられる量である。
    pub(super) fn 合力と法線の合計の比(&self) -> f64 {
        if self.法線の乗数の合計 > 0.0 {
            self.接線の合力の大きさ / self.法線の乗数の合計
        } else {
            0.0
        }
    }

    pub(super) fn 円錐の内側か(&self) -> bool {
        self.円錐の内側か
    }

    /// 解けなかった結末の読み取り。乗数も拘束違反も読めないため、綴りだけを持つ。
    pub(super) fn 解けなかった結末から組む(結末の綴り: &'static str) -> Self {
        Self::六つの量から組む(結末の綴り, Vec::new(), Vec::new(), 0.0, 0.0, false)
    }
}
