//! 滑走中の坂の箱の細分1本の法線の収支の読み取りと、その窓の統計(PR #97 の受理阻害2の診断の材料)。
//! 位置の反復の Σλ_n と速度段階の反発の口が与えた法線の衝撃 Σj_n の2つを、どちらも解析の法線力積 m g cosθ h² で割った比で持つ。
//! 真の食い込みは、確定した配置の底面の4つの角を倍精度で評価した位置から坂の面までの距離で求める(非貫通の行が読む
//! 隔たりと突き合わせるため)。統計は、単純平均のほかに、揺れの上に乗った平均が信頼できるかを見るための中央値・
//! 上下1割を落とした平均・窓の長さを120から全長まで変えた部分平均の最小と最大を持つ。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の2段の位置_2026-09-08.md`

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, 変位};

use super::super::slope_geometry::坂の場面の条件;
use super::super::substep_harness::一つの箱と静的な直方体の場面;

const 坂の半分の長さ: f64 = 20.0;
const 部分平均の最短の長さ: usize = 120;

/// 細分1本の法線の収支。比はどれも解析の法線力積 m g cosθ h² で割った値である。
pub(super) struct 細分の法線の収支 {
    pub(super) 位置の比: f64,
    pub(super) 速度段階の法線の比: f64,
    pub(super) 動摩擦の衝撃: f64,
    pub(super) 角速度の大きさ: f64,
    pub(super) 観測の食い込み: f64,
    pub(super) 真の食い込み: f64,
    pub(super) 反力の無い点の数: usize,
}

impl 細分の法線の収支 {
    /// 直前の細分の観測と確定した配置から読む。刻み幅を掛けるのは、速度段階の衝撃(ニュートン秒)を位置の乗数と同じ次元へ揃えるためである。
    pub(super) fn 場面から読む(場面: &一つの箱と静的な直方体の場面, 条件: &坂の場面の条件, 解析値: f64) -> Self {
        let 観測 = 場面.直前の細分の観測;
        let 刻み幅 = f64::from(場面.刻み幅.秒().値());
        Self {
            位置の比: f64::from(観測.法線の乗数の合計.値()) / 解析値,
            速度段階の法線の比: f64::from(観測.速度段階の法線の衝撃の合計.値()) * 刻み幅 / 解析値,
            動摩擦の衝撃: f64::from(観測.速度段階の動摩擦の衝撃の合計.値()),
            角速度の大きさ: f64::from(場面.箱の運動状態.角速度().長さ().値()),
            観測の食い込み: f64::from(観測.最大の食い込み.値()),
            真の食い込み: 真の食い込み(場面, 条件),
            反力の無い点の数: 観測.法線反力の無い点の数,
        }
    }
}

// 確定した配置の底面の4つの角のうち、坂の面へ最も深く入った長さ。面より上なら零である。
fn 真の食い込み(場面: &一つの箱と静的な直方体の場面, 条件: &坂の場面の条件) -> f64 {
    let 法線 = 条件.坂の面の法線();
    let 坂の中心 = 場面.静的な直方体.中心();
    let (正, 負) = (メートル::生成する(0.5), メートル::生成する(-0.5));
    [(正, 負, 正), (正, 負, 負), (負, 負, 正), (負, 負, 負)]
        .into_iter()
        .map(|(x, y, z)| {
            let 角 = 場面.箱の配置.局所点の世界位置(変位::成分から生成する(x, y, z)).倍精度で評価した位置();
            let 面までの高さ = (角.x().値() - f64::from(坂の中心.x().値())) * f64::from(法線.x())
                + (角.y().値() - f64::from(坂の中心.y().値())) * f64::from(法線.y())
                + (角.z().値() - f64::from(坂の中心.z().値())) * f64::from(法線.z())
                - 坂の半分の長さ;
            (-面までの高さ).max(0.0)
        })
        .fold(0.0, f64::max)
}

/// 窓の統計: 平均・中央値・上下1割を落とした平均・部分平均の最小と最大。
pub(super) struct 窓の統計 {
    pub(super) 平均: f64,
    pub(super) 中央値: f64,
    pub(super) 上下一割を落とした平均: f64,
    pub(super) 部分平均の最小: f64,
    pub(super) 部分平均の最大: f64,
}

impl 窓の統計 {
    pub(super) fn 並びから求める(並び: &[f64]) -> Self {
        let 本数 = 並び.len();
        let mut 昇順 = 並び.to_vec();
        昇順.sort_by(f64::total_cmp);
        let 落とす = 本数 / 10;
        let 中程 = &昇順[落とす..本数 - 落とす];
        let 部分平均: Vec<f64> = (部分平均の最短の長さ..=本数).map(|長さ| 平均(&並び[..長さ])).collect();
        Self {
            平均: 平均(並び),
            中央値: 昇順[本数 / 2],
            上下一割を落とした平均: 平均(中程),
            部分平均の最小: 部分平均.iter().copied().fold(f64::MAX, f64::min),
            部分平均の最大: 部分平均.iter().copied().fold(f64::MIN, f64::max),
        }
    }
}

fn 平均(並び: &[f64]) -> f64 {
    並び.iter().sum::<f64>() / f64::from(u32::try_from(並び.len()).unwrap())
}
