//! 滑走中の坂の箱の法線の収支と減速度の誤差を、箱の半分の長さ(接触点から重心までの腕の長さ)ごとに綴る計器
//! (Issue #98 の反証1の診断。合否は判定しない)。
//! 綴るのは、箱の半分の長さと動摩擦係数の組ごとに、位置の反復の Σλ_n の比の平均、速度段階の法線の口が与えた
//! 衝撃に刻み幅を掛けた比の平均、2つの和、速度段階の後の角速度の大きさの平均、および減速度の解析値
//! g(sinθ − μ_d cosθ) からの相対誤差である。角速度を綴るのは、それが機構の途中の量(動摩擦の衝撃が作る回転)だからである。
//! 比の分母はどれも解析の法線力積 m g cosθ h² であり、箱の質量が1キログラムで固定であるため箱の大きさに依らない。
//! 測るのは、Issue #98 が原因として挙げる機構(接触点が重心より下にあるため動摩擦の衝撃が箱を傾け、その回転が
//! 法線方向の接近の速さを作り、速度段階がそれを消す)が腕の長さに依存するかである。
//! 窓は `sliding_normal_impulse_record` の表19と同じ細分60から300の240本であり、減速度も同じ窓で測る。
//! 実行は `cargo test -p blitz_sim --release 滑走の法線の収支と減速度の誤差を箱の半分の長さごとに記録する -- --ignored --nocapture` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の2段の位置_2026-09-08.md`

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::super::super::friction_coefficient::摩擦係数;
use super::super::slope_fixture::坂の場面を指定で組む;
use super::super::slope_geometry::{坂の場面の条件, 滑走の加速度, 重力の大きさ};
use super::super::slope_scene_spec::坂の場面の組み立ての指定;
use super::super::static_friction_method::場面の静止摩擦の解き方;

const 滑る傾きの正接: f32 = 0.9;
const 静止摩擦係数の値: f32 = 0.6;
const 下り向きの初速: f32 = 1.0;
const 測り始めるまでの細分数: usize = 60;
const 測る細分数: usize = 240;
const 測る秒数: f32 = 0.5; // 測る細分数 ÷ (1細分の刻み幅 1/480秒)
// 振る値をスライスで持つのは、単精度の3つ組の宣言を剛体のモジュール群で禁じる規約(剛体の状態と接触の判断5)に触れないためである。
// この3つは座標の成分ではなく、独立に振る長さの並びである。
const 振る箱の半分の長さ: &[f32] = &[0.5, 0.25, 0.1];
const 振る動摩擦係数: [f32; 2] = [0.1, 0.55];

/// 箱の半分の長さと動摩擦係数の1つの組で測った法線の収支と減速度の誤差。
struct 一つの組の法線の収支と減速度の誤差 {
    位置の比の平均: f64,
    速度段階の法線の比の平均: f64,
    角速度の大きさの平均: f64,
    減速度の相対誤差: f64,
}

// 細分1本あたりの法線力積の解析値 m g cosθ h²。質量1キログラム、細分の刻み幅は1/480秒である。
fn 法線力積の解析値() -> f64 {
    let 正接 = f64::from(滑る傾きの正接);
    let 余弦 = 1.0 / (1.0 + 正接 * 正接).sqrt();
    f64::from(重力の大きさ) * 余弦 / (480.0 * 480.0)
}

fn 動摩擦係数から坂の場面の条件を組む(動摩擦係数の値: f32) -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接: 滑る傾きの正接,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(静止摩擦係数の値).unwrap(),
        動摩擦係数: 摩擦係数::生成する(動摩擦係数の値).unwrap(),
        下り向きの初速,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    }
}

fn 箱の半分の長さと動摩擦係数の組を測る(箱の半分の長さの値: f32, 動摩擦係数の値: f32) -> 一つの組の法線の収支と減速度の誤差 {
    let 条件 = 動摩擦係数から坂の場面の条件を組む(動摩擦係数の値);
    let 指定 = 坂の場面の組み立ての指定 {
        箱の半分の長さ: メートル::生成する(箱の半分の長さの値),
        ..坂の場面の組み立ての指定::既定()
    };
    let mut 場面 = 坂の場面を指定で組む(&条件, &指定);
    let 刻み幅の秒 = f64::from(場面.刻み幅.秒().値());
    let 解析値 = 法線力積の解析値();
    場面.細分を進める(測り始めるまでの細分数);
    let 初めの速さ = 場面.下り向きの速さ(&条件);
    let (mut 位置の比の合計, mut 速度段階の法線の比の合計, mut 角速度の大きさの合計) = (0.0, 0.0, 0.0);
    for _ in 0..測る細分数 {
        場面.一細分進める();
        let 観測 = 場面.直前の細分の観測;
        位置の比の合計 += f64::from(観測.法線の乗数の合計.値()) / 解析値;
        速度段階の法線の比の合計 += f64::from(観測.速度段階の法線の衝撃の合計.値()) * 刻み幅の秒 / 解析値;
        角速度の大きさの合計 += f64::from(場面.箱の運動状態.角速度().長さ().値());
    }
    let 測った加速度 = (場面.下り向きの速さ(&条件) - 初めの速さ) / 測る秒数;
    let 解析の加速度 = 滑走の加速度(滑る傾きの正接, 動摩擦係数の値);
    let 本数 = f64::from(u32::try_from(測る細分数).unwrap());
    一つの組の法線の収支と減速度の誤差 {
        位置の比の平均: 位置の比の合計 / 本数,
        速度段階の法線の比の平均: 速度段階の法線の比の合計 / 本数,
        角速度の大きさの平均: 角速度の大きさの合計 / 本数,
        減速度の相対誤差: f64::from((測った加速度 - 解析の加速度).abs() / 解析の加速度),
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 滑走の法線の収支と減速度の誤差を箱の半分の長さごとに記録する() {
    println!("箱の半分の長さ | 動摩擦係数 | Σλ_nの比の平均 | 速度段階の法線の比の平均 | 2つの和 | 角速度の大きさの平均 | 減速度の相対誤差");
    for &箱の半分の長さの値 in 振る箱の半分の長さ {
        for 動摩擦係数の値 in 振る動摩擦係数 {
            let 読み = 箱の半分の長さと動摩擦係数の組を測る(箱の半分の長さの値, 動摩擦係数の値);
            println!(
                "{箱の半分の長さの値} | {動摩擦係数の値} | {:.6} | {:.6} | {:.6} | {:.6e} | {:.6e}",
                読み.位置の比の平均,
                読み.速度段階の法線の比の平均,
                読み.位置の比の平均 + 読み.速度段階の法線の比の平均,
                読み.角速度の大きさの平均,
                読み.減速度の相対誤差
            );
        }
    }
}
