//! 保持する組と滑走する組が分かれる細分を探して内訳を綴る計器(Issue #59の原因の環の特定)。
//! 3つの対を見る。許容差の倍率だけが違う対、鉛直軸まわりの回しだけが違う対、世界内の置き方だけが違う対である。
//! どの対も、Issue #59が挙げた「解法の許容差が物理の判定へ入っている」ことを別の入口から示した場所である。
//! 綴るのは、細分ごとの単精度と倍精度の読み取り(結末・Σλ_n・‖Σλ_t‖・その比・円錐の判定・点ごとの C_n と C_t・
//! 捨てた固有の向きと理由・行ごとの残差)と、その細分の終わりに位置から再構成された坂の下り向きの速さである。
//! 速さを一緒に綴るのは、Issue #59の連鎖の「残差 → 速度再構成 → 次細分の予測」の環を見るためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

