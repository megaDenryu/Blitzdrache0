// 綴る初めの細分の本数。初めの食い込みを解く過渡がこの範囲に入る。
const 初めに綴る細分の本数: usize = 4;
// 円錐を初めて超えた細分を探す上限。600刻みは4800細分であり、その範囲を覆う。
const 円錐を超える細分を探す上限: usize = 4800;

fn 回しのラジアン(回しの度: f32) -> f32 {
    ラジアン::度から(回しの度).値()
}

// 分類が1つの条件だけで分かれた3つの対。どれも56c0e642の表で観測した組み合わせである。
fn 見る対の並び() -> Vec<分類が分かれる組の対> {
    vec![
        分類が分かれる組の対 {
            見出し: "許容差の倍率だけが違う対(正接0.50・回し0度)",
            保持する側の名前: "許容差1倍",
            保持する側: 数値契約の診断の一つの場合::許容差の倍率から生成する(0.0, 0.50, 1.0),
            滑走する側の名前: "許容差0.5倍",
            滑走する側: 数値契約の診断の一つの場合::許容差の倍率から生成する(0.0, 0.50, 0.5),
        },
        分類が分かれる組の対 {
            見出し: "鉛直軸まわりの回しだけが違う対(正接0.55・既定の置き方)",
            保持する側の名前: "回し30度",
            保持する側: 数値契約の診断の一つの場合::回しと正接から生成する(回しのラジアン(30.0), 0.55),
            滑走する側の名前: "回し0度",
            滑走する側: 数値契約の診断の一つの場合::回しと正接から生成する(0.0, 0.55),
        },
        分類が分かれる組の対 {
            見出し: "世界内の置き方だけが違う対(正接0.50・回し0度)",
            保持する側の名前: "既定の置き方(約20.5メートル)",
            保持する側: 数値契約の診断の一つの場合::回しと正接から生成する(0.0, 0.50),
            滑走する側の名前: "原点付近(法線の向きへ−20.4999メートル)",
            滑走する側: 数値契約の診断の一つの場合::法線の向きへ動かして生成する(
                0.0,
                0.50,
                メートル::生成する(-20.4999),
            ),
        },
    ]
}

// 1つの側の、指定の細分の第一反復と細分の終わりの速さを綴る。
fn 一つの側の一細分を綴る(名前: &str, 場合: &数値契約の診断の一つの場合, 細分の番号: usize) {
    let 見出し = format!("{名前}_細分{細分の番号}");
    match 場合.指定の細分の第一反復を二つの精度で読む(細分の番号) {
        Some(読み取り) => {
            読み取り.綴る(&見出し);
            if 読み取り.円錐の判定が食い違ったか() {
                println!("  [食い違い] この地点で2つの経路の結末か円錐の判定が違う");
            }
        }
        None => println!("[{見出し}] 接触点集合が無い"),
    }
    println!(
        "  細分の終わりに位置から再構成された下り向きの速さ={:.9e}",
        場合.指定の細分までの下り向きの速さ(細分の番号)
    );
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 分類が分かれる組の対が分岐する細分を記録する() {
    for 対 in 見る対の並び() {
        println!("=== {} ===", 対.見出し);
        for (名前, 場合) in 対.二つの側() {
            match 場合.円錐を初めて超えた細分の番号(円錐を超える細分を探す上限) {
                Some(番号) => println!("[{名前}] 円錐を初めて超えた細分は{番号}本目である"),
                None => println!("[{名前}] {円錐を超える細分を探す上限}細分のあいだ円錐を超えなかった"),
            }
        }
        for 細分の番号 in 対.綴る細分の番号(初めに綴る細分の本数, 円錐を超える細分を探す上限) {
            for (名前, 場合) in 対.二つの側() {
                一つの側の一細分を綴る(名前, 場合, 細分の番号);
            }
        }
    }
}
