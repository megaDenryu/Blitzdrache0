//! 数値契約の診断が測る1つの場合(Issue #59)。坂の傾きの正接・鉛直軸まわりの回し・坂の面の法線の向きへ場面ごと
//! 動かす長さの3つで決まる。動かす長さを持つのは、同じ相対配置を世界内で平行移動して接触点の座標の表現の刻みを
//! 変える診断が要るためである。
//! `cone_breach_record/recorded_case`と重なるのは、回しと正接から坂の場面の条件を組む2行だけである。あちらは
//! 円錐を初めて超える細分を探す走査を持ち、こちらは保持と滑走の分類と2つの精度の比較を持つ。測る対象が違うため
//! 型を分けている。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::super::super::friction_coefficient::摩擦係数;
use super::super::super::normal_tangential_system::解けたと見なす許容差の倍率;
use super::super::slope_fixture::{一刻みの細分数, 坂の場面を移動と許容差の倍率で組む};
use super::super::slope_geometry::坂の場面の条件;
use super::super::static_friction_method::場面の静止摩擦の解き方;
use super::super::substep_harness::一つの箱と静的な直方体の場面;
use super::comparison_substep::二つの精度の読み取り;
use super::holding_class::保持と滑走の分類;

pub(super) const 静止摩擦係数の値: f32 = 0.6;
const 動摩擦係数の値: f32 = 0.2;

/// 診断が測る1つの場合。
pub(super) struct 数値契約の診断の一つの場合 {
    pub(super) 鉛直軸まわりの回し: f32,
    pub(super) 傾きの正接: f32,
    pub(super) 法線の向きへ動かす長さ: メートル,
    pub(super) 解けたと見なす許容差の倍率: 解けたと見なす許容差の倍率,
}

impl 数値契約の診断の一つの場合 {
    pub(super) fn 回しと正接から生成する(鉛直軸まわりの回し: f32, 傾きの正接: f32) -> Self {
        Self {
            鉛直軸まわりの回し,
            傾きの正接,
            法線の向きへ動かす長さ: メートル::生成する(0.0),
            解けたと見なす許容差の倍率: 解けたと見なす許容差の倍率::既定(),
        }
    }

    /// 解けたと見なす許容差だけを振った場合。世界座標も相対の配置も変えない。
    pub(super) fn 許容差の倍率から生成する(鉛直軸まわりの回し: f32, 傾きの正接: f32, 許容差の比: f32) -> Self {
        Self {
            鉛直軸まわりの回し,
            傾きの正接,
            法線の向きへ動かす長さ: メートル::生成する(0.0),
            解けたと見なす許容差の倍率: 解けたと見なす許容差の倍率::比から生成する(許容差の比),
        }
    }

    /// 坂と箱をまとめて坂の面の法線の向きへ動かした場合。相対の配置は変わらず、座標の表現の刻みだけが変わる。
    pub(super) fn 法線の向きへ動かして生成する(
        鉛直軸まわりの回し: f32, 傾きの正接: f32, 法線の向きへ動かす長さ: メートル
    ) -> Self {
        Self {
            鉛直軸まわりの回し,
            傾きの正接,
            法線の向きへ動かす長さ,
            解けたと見なす許容差の倍率: 解けたと見なす許容差の倍率::既定(),
        }
    }

    fn 場面を組む(&self, 条件: &坂の場面の条件) -> 一つの箱と静的な直方体の場面 {
        坂の場面を移動と許容差の倍率で組む(条件, self.法線の向きへ動かす長さ, self.解けたと見なす許容差の倍率)
    }

    fn 坂の場面の条件を組む(&self) -> 坂の場面の条件 {
        坂の場面の条件 {
            傾きの正接: self.傾きの正接,
            鉛直軸まわりの回し: self.鉛直軸まわりの回し,
            静止摩擦係数: 摩擦係数::生成する(静止摩擦係数の値).unwrap(),
            動摩擦係数: 摩擦係数::生成する(動摩擦係数の値).unwrap(),
            下り向きの初速: 0.0,
            静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
        }
    }

    /// 指定の刻み数だけ進めた後の、坂に沿った変位と保持と滑走の分類。
    pub(super) fn 刻みを進めて分類する(&self, 刻み数: usize) -> 保持と滑走の分類 {
        let 条件 = self.坂の場面の条件を組む();
        let mut 場面 = self.場面を組む(&条件);
        let 初めの重心 = 場面.箱の配置.重心の位置();
        場面.細分を進める(刻み数 * 一刻みの細分数);
        保持と滑走の分類::坂に沿った変位と滑走中の点から決める(
            場面.坂に沿った変位(初めの重心, &条件),
            場面.直前の細分の観測.滑走中の接触点の数,
        )
    }

    /// 指定の細分まで進めてから、その次の細分の第一反復を単精度と倍精度で読む。
    pub(super) fn 指定の細分の第一反復を二つの精度で読む(&self, 細分の番号: usize) -> Option<二つの精度の読み取り> {
        let 条件 = self.坂の場面の条件を組む();
        let mut 場面 = self.場面を組む(&条件);
        場面.細分を進める(細分の番号);
        場面.次の細分の第一反復を二つの精度で読む()
    }
}
