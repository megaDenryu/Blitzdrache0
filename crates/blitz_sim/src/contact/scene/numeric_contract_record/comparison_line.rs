//! 単精度と倍精度の読み取りを1つの行の束として綴る工程(Issue #59の数値契約の診断)。
//! 綴るのは、2つの経路の結末・Σλ_n・‖Σλ_t‖・その比・円錐の判定と、点ごとの法線の拘束違反と接線変位である。
//! 読み取りの型(`candidate_reading`)から分けているのは、こちらが表の書式を持ち、あちらが値を持つからである。
//! 比を必ず綴るのは、保持と滑走を分ける量がこの比だからである。2つの経路で比が同じなら、その細分の判定の差は
//! 数値の精度から来ていない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::comparison_substep::二つの精度の読み取り;

impl 二つの精度の読み取り {
    /// 1地点の2つの読み取りを綴る。見出しは呼び出し側が組んだ場合の名前である。
    pub(super) fn 綴る(&self, 見出し: &str) {
        println!("[{見出し}] 単精度={} 倍精度={}", self.単精度.結末の綴り(), self.倍精度.結末の綴り());
        println!(
            "  Σλ_n 単精度={:.9e} 倍精度={:.9e} | ‖Σλ_t‖ 単精度={:.9e} 倍精度={:.9e}",
            self.単精度.法線の乗数の合計(),
            self.倍精度.法線の乗数の合計(),
            self.単精度.接線の合力の大きさ(),
            self.倍精度.接線の合力の大きさ(),
        );
        println!(
            "  比 単精度={:.9} 倍精度={:.9} 差={:.3e} | 円錐の内側か 単精度={} 倍精度={}",
            self.単精度.合力と法線の合計の比(),
            self.倍精度.合力と法線の合計の比(),
            self.単精度.合力と法線の合計の比() - self.倍精度.合力と法線の合計の比(),
            self.単精度.円錐の内側か(),
            self.倍精度.円錐の内側か(),
        );
        self.点ごとを綴る();
    }

    /// 2つの経路で円錐の判定が食い違ったか。表の要約が読む。
    pub(super) fn 円錐の判定が食い違ったか(&self) -> bool {
        self.単精度.円錐の内側か() != self.倍精度.円錐の内側か() || self.単精度.結末の綴り() != self.倍精度.結末の綴り()
    }

    fn 点ごとを綴る(&self) {
        let 点数 = self.単精度.点ごとの法線の拘束違反().len().min(self.倍精度.点ごとの法線の拘束違反().len());
        for 番号 in 0..点数 {
            println!(
                "  点{番号} C_n 単精度={:.9e} 倍精度={:.9e} | C_t 単精度={:.9e} 倍精度={:.9e}",
                self.単精度.点ごとの法線の拘束違反()[番号],
                self.倍精度.点ごとの法線の拘束違反()[番号],
                self.単精度.点ごとの接線変位()[番号],
                self.倍精度.点ごとの接線変位()[番号],
            );
        }
    }
}
