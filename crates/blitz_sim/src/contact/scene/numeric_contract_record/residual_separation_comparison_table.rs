//! 判断24の候補D(残差の変化を速度から除く)のあり/なしで、坂の境界・世界内の平行移動・解法の許容差の分類を並べる計器
//! (Issue #59の第3段階。候補Bの導入後の比較)。合否は判定せず、表を作るだけである。
//! 候補Dが不要になったから削るのではなく、残差を物理の速度として扱わないという意味が独立に成立しているかをオーナーが
//! 判断する材料であるため、3つの走査を同じ場合の組でDありとDなしの2列に並べる。
//! 実行は `cargo test -p blitz_sim --release 残差の変化を速度から除くか運ばせるかで保持と滑走の分類を並べて記録する -- --ignored --nocapture` である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

#![cfg(test)]

use blitz_math::メートル;

use super::super::residual_separation::場面の残差の分離;
use super::diagnostic_case::数値契約の診断の一つの場合;

const 振る傾きの正接: &[f32] = &[0.50, 0.55, 0.61];
const 振る鉛直軸まわりの回しの度: &[f32] = &[0.0, 30.0, 45.0];
const 振る許容差の比: &[f32] = &[0.5, 2.0];
const 振る動かす長さのメートル: &[f32] = &[-20.4999, 20.4999];
const 見る刻み数: usize = 600;

// 1つの場合をDありとDなしで走らせ、「分類(変位)」の対を1つの欄に綴る。
fn 二つの経路の欄(場合: 数値契約の診断の一つの場合) -> String {
    let 除く = 場合.刻みを進めて分類する(見る刻み数);
    let 運ばせる = 場合
        .残差の分離を変える(場面の残差の分離::残差の変化を速度へ運ばせる)
        .刻みを進めて分類する(見る刻み数);
    format!(
        "Dあり {}({:.3e}) / Dなし {}({:.3e})",
        除く.綴り(),
        除く.坂に沿った変位(),
        運ばせる.綴り(),
        運ばせる.坂に沿った変位()
    )
}

fn 行を綴る(見出し: &str, 場合を組む: impl Fn(f32, f32) -> 数値契約の診断の一つの場合) {
    for 回しの度 in 振る鉛直軸まわりの回しの度.iter().copied() {
        let 欄: Vec<String> = 振る傾きの正接.iter().map(|正接| 二つの経路の欄(場合を組む(回しの度, *正接))).collect();
        println!("{見出し} | {回しの度}度 | {}", 欄.join(" | "));
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 残差の変化を速度から除くか運ばせるかで保持と滑走の分類を並べて記録する() {
    println!("刻み数={見る刻み数} 欄は 正接0.50 | 正接0.55 | 正接0.61");
    println!("[坂の境界] 既定の置き方・許容差1倍");
    行を綴る("既定", |回しの度, 正接| {
        数値契約の診断の一つの場合::回しの度と正接から生成する(回しの度, 正接)
    });
    println!("[世界内の平行移動] 動かす長さ(メートル)");
    for 動かす長さ in 振る動かす長さのメートル.iter().copied() {
        行を綴る(&format!("{動かす長さ}"), |回しの度, 正接| {
            数値契約の診断の一つの場合::回しの度と法線の向きへ動かす長さから生成する(
                回しの度,
                正接,
                メートル::生成する(動かす長さ),
            )
        });
    }
    println!("[解法の許容差] 許容差の倍率");
    for 許容差の比 in 振る許容差の比.iter().copied() {
        行を綴る(&format!("{許容差の比}倍"), |回しの度, 正接| {
            数値契約の診断の一つの場合::回しの度と許容差の倍率から生成する(回しの度, 正接, 許容差の比)
        });
    }
}
