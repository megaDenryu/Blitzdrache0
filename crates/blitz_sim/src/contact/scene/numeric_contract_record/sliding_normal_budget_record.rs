//! 滑走中の坂の箱の法線の収支を細分ごとに読み、窓の統計と、同じ細分を倍精度の参照で解いた Σλ_n の比を綴る計器
//! (PR #97 の受理阻害2の診断。合否は判定しない)。
//! 綴るのは、動摩擦係数ごとに、位置の反復の Σλ_n の比(平均・中央値・上下1割を落とした平均・部分平均の最小と最大)、
//! 速度段階の反発の口が与えた法線の衝撃の比の平均、2つの和の平均、動摩擦の衝撃の平均、速度段階の後の角速度の大きさの平均、
//! 非貫通の行が読む食い込みと真の食い込みの平均とその差、法線反力の無い点の延べ数、そして窓の中の4つの細分で
//! 次の細分の第一反復の入口を単精度と倍精度で読んだ Σλ_n の比である。
//! 倍精度の読みは場面の履歴を書き換えるため、読む細分ごとに新しい場面を同じ本数だけ進めて読む。
//! 実行は `cargo test -p blitz_sim --release 滑走中の法線の収支と倍精度の参照の比を記録する -- --ignored --nocapture` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の2段の位置_2026-09-08.md`

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::super::super::friction_coefficient::摩擦係数;
use super::super::slope_fixture::坂の場面を組む;
use super::super::slope_geometry::{坂の場面の条件, 重力の大きさ};
use super::super::static_friction_method::場面の静止摩擦の解き方;
use super::sliding_normal_budget_sample::{窓の統計, 細分の法線の収支};

const 滑る傾きの正接: f32 = 0.9;
const 静止摩擦係数の値: f32 = 0.6;
const 下り向きの初速: f32 = 1.0;
const 測り始めるまでの細分数: usize = 60;
const 測る細分数: usize = 480;
const 振る動摩擦係数: [f32; 2] = [0.2, 0.55];
const 倍精度で読む窓の中の細分: [usize; 4] = [0, 120, 240, 360];

fn 条件(動摩擦係数の値: f32) -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接: 滑る傾きの正接,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(静止摩擦係数の値).unwrap(),
        動摩擦係数: 摩擦係数::生成する(動摩擦係数の値).unwrap(),
        下り向きの初速,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    }
}

// 細分1本あたりの法線力積の解析値 m g cosθ h²。質量1キログラム、細分の刻み幅は1/480秒である。
fn 法線力積の解析値() -> f64 {
    let 正接 = f64::from(滑る傾きの正接);
    let 余弦 = 1.0 / (1.0 + 正接 * 正接).sqrt();
    f64::from(重力の大きさ) * 余弦 / (480.0 * 480.0)
}

fn 窓を読む(条件: &坂の場面の条件) -> Vec<細分の法線の収支> {
    let mut 場面 = 坂の場面を組む(条件);
    場面.細分を進める(測り始めるまでの細分数);
    (0..測る細分数)
        .map(|_| {
            場面.一細分進める();
            細分の法線の収支::場面から読む(&場面, 条件, 法線力積の解析値())
        })
        .collect()
}

// 窓の中の指定の細分まで新しい場面を進め、次の細分の第一反復の入口の Σλ_n を単精度と倍精度で読んだ比。
fn 倍精度の参照の比を読む(条件: &坂の場面の条件, 窓の中の細分: usize) -> (f64, f64) {
    let mut 場面 = 坂の場面を組む(条件);
    場面.細分を進める(測り始めるまでの細分数 + 窓の中の細分);
    let 読み取り = 場面.次の細分の第一反復を二つの精度で読む().unwrap();
    (
        読み取り.単精度.法線の乗数の合計() / 法線力積の解析値(),
        読み取り.倍精度.法線の乗数の合計() / 法線力積の解析値(),
    )
}

fn 平均(並び: impl Iterator<Item = f64>, 本数: usize) -> f64 {
    並び.sum::<f64>() / f64::from(u32::try_from(本数).unwrap())
}

fn 一つの係数を綴る(動摩擦係数の値: f32) {
    let 条件 = 条件(動摩擦係数の値);
    let 窓 = 窓を読む(&条件);
    let 本数 = 窓.len();
    let 位置 = 窓の統計::並びから求める(&窓.iter().map(|量| 量.位置の比).collect::<Vec<_>>());
    let 速度段階 = 平均(窓.iter().map(|量| 量.速度段階の法線の比), 本数);
    println!("[動摩擦係数{動摩擦係数の値}] 窓={測る細分数}本");
    println!(
        "  Σλ_nの比: 平均={:.6} 中央値={:.6} 上下1割を落とした平均={:.6} 部分平均の最小={:.6} 最大={:.6}",
        位置.平均, 位置.中央値, 位置.上下一割を落とした平均, 位置.部分平均の最小, 位置.部分平均の最大
    );
    println!(
        "  速度段階の法線の衝撃×hの比の平均={速度段階:.6} 2つの和の平均={:.6} 動摩擦の衝撃の平均={:.6e} 角速度の大きさの平均={:.6e}",
        位置.平均 + 速度段階,
        平均(窓.iter().map(|量| 量.動摩擦の衝撃), 本数),
        平均(窓.iter().map(|量| 量.角速度の大きさ), 本数)
    );
    println!(
        "  行が読む食い込みの平均={:.6e} 真の食い込みの平均={:.6e} 差(行−真)の平均={:.6e} 法線反力の無い点の延べ数={}",
        平均(窓.iter().map(|量| 量.観測の食い込み), 本数),
        平均(窓.iter().map(|量| 量.真の食い込み), 本数),
        平均(窓.iter().map(|量| 量.観測の食い込み - 量.真の食い込み), 本数),
        窓.iter().map(|量| 量.反力の無い点の数).sum::<usize>()
    );
    for 細分 in 倍精度で読む窓の中の細分 {
        let (単精度, 倍精度) = 倍精度の参照の比を読む(&条件, 細分);
        println!("  窓の細分{細分}の次の第一反復の入口: 単精度のΣλ_nの比={単精度:.6} 倍精度の参照の比={倍精度:.6}");
    }
}

