//! 細分1本の位置の反復の1回目を、単精度と倍精度の両方で読む工程(Issue #59の数値契約の診断)。
//! 予測・接触点集合・履歴の併走までを本番と同じ順で行い、まだ1度も補正を適用していない配置で2つの経路を読む。
//! 細分の残り(補正の適用・速度の再構成・速度段階・履歴の書き戻し)は行わない。この工程は場面を進めるためでなく、
//! 進んだ場面の1地点を観測するためにあり、観測した細分は捨てるからである。
//! `cone_breach_record/instrumented_substep`と同じ形だが、あちらが位置の反復の3つの地点を綴るのに対し、
//! こちらは1回目の反復の入口で2つの精度を並べる。比べる相手を揃えるには、どちらの経路もまだ補正を受けていない
//! 同じ配置から出発しなければならない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」

#![cfg(test)]

use super::super::super::normal_tangential_system::倍精度の解の内訳;
use super::super::substep_harness::一つの箱と静的な直方体の場面;
use super::candidate_reading::粘着の候補の読み取り;
use crate::rigid_body::一刻みの入力;
use crate::rigid_xpbd::姿勢自由度の参加者;

/// 同じ1地点を2つの精度で読んだ組。
pub(super) struct 二つの精度の読み取り {
    pub(super) 単精度: 粘着の候補の読み取り,
    pub(super) 倍精度: 粘着の候補の読み取り,
    pub(super) 倍精度の内訳: Option<倍精度の解の内訳>,
}

impl 一つの箱と静的な直方体の場面 {
    /// 次の細分の位置の反復の1回目の入口を、単精度と倍精度で読む。接触点集合が無ければ無しである。
    /// 注意: 配置と運動状態は進めないが、履歴の併走はこの場面の履歴を書き換える。呼び出した場面はここで捨てる。
    pub(super) fn 次の細分の第一反復を二つの精度で読む(&mut self) -> Option<二つの精度の読み取り> {
        let (前の状態, 予測, _) =
            self.予測器
                .動的剛体を予測する(&self.箱の配置, &self.箱の運動状態, &self.箱の質量特性, &一刻みの入力::無し());
        let mut バッチ = self.接触拘束のバッチを組む(&予測);
        let _ = self.履歴の記録を引き継ぐ(&mut バッチ, &前の状態.保存した配置());
        if バッチ.剛体と静的世界の接触点集合の数() == 0 {
            return None;
        }
        let 接触点集合 = バッチ.剛体と静的世界の接触点集合を反復のために借りる(0).to_vec();
        let 参加者 = 姿勢自由度の参加者::動的(*予測.配置(), &self.箱の質量特性);
        let (倍精度, 倍精度の内訳) = self.倍精度で粘着の候補を読む(&接触点集合, 予測.配置());
        Some(二つの精度の読み取り {
            単精度: self.単精度で粘着の候補を読む(&接触点集合, &参加者),
            倍精度,
            倍精度の内訳,
        })
    }
}
