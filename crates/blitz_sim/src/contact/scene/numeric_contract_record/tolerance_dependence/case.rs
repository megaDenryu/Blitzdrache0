//! 許容差依存の診断が測る1つの場合(Issue #59の第4段階)。静止摩擦係数・傾きの正接・鉛直軸まわりの回しの度・
//! 解けたと見なす許容差の倍率・接線の行の右辺の δ の扱いの5つと、段階A2が段階A1の場面から1つだけ変える点で決まる。`diagnostic_case`と分けているのは、
//! あちらが静止摩擦係数を0.6に固定しており、この診断が反例として静止摩擦係数0.8の同じ組を要るためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::ラジアン;

use super::super::holding_class::保持と滑走の分類;
use super::scene_variation::段階A1の場面からの一つの変更;
use crate::contact::friction_coefficient::摩擦係数;
use crate::contact::normal_tangential_system::{
    接線の行への許容差の適用規則, 解けたと見なす許容差の倍率, 試験の許容差の適用規則
};
use crate::contact::scene::slope_fixture::坂の場面を指定で組む;
use crate::contact::scene::slope_geometry::坂の場面の条件;
use crate::contact::scene::static_friction_method::場面の静止摩擦の解き方;
use crate::contact::scene::substep_harness::一つの箱と静的な直方体の場面;

const 動摩擦係数の値: f32 = 0.2;

/// 許容差依存の診断が測る1つの場合。
pub(super) struct 許容差依存の診断の場合 {
    pub(super) 静止摩擦係数の値: f32,
    pub(super) 傾きの正接: f32,
    pub(super) 鉛直軸まわりの回しの度: f32,
    pub(super) 許容差の比: f32,
    pub(super) 行への適用規則: 接線の行への許容差の適用規則,
    pub(super) 変更: 段階A1の場面からの一つの変更,
}

impl 許容差依存の診断の場合 {
    pub(super) fn 坂の場面の条件を組む(&self) -> 坂の場面の条件 {
        坂の場面の条件 {
            傾きの正接: self.傾きの正接,
            鉛直軸まわりの回し: ラジアン::度から(self.鉛直軸まわりの回しの度).値(),
            静止摩擦係数: 摩擦係数::生成する(self.静止摩擦係数の値).unwrap(),
            動摩擦係数: 摩擦係数::生成する(動摩擦係数の値).unwrap(),
            下り向きの初速: 0.0,
            静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
        }
    }

    /// 段階A1の場面から1つだけ変えた坂の場面を組み、計測の始点(休ませる変更なら休ませて重力を戻した後)まで進める。
    pub(super) fn 場面を組む(&self) -> 一つの箱と静的な直方体の場面 {
        self.場面を適用規則で組む(self.許容差の適用規則())
    }

    /// この場合の場面を、指定の許容差の適用規則で組む。届く先や閾値の倍率を振る計器が読む。
    pub(super) fn 場面を適用規則で組む(
        &self, 適用規則: 試験の許容差の適用規則
    ) -> 一つの箱と静的な直方体の場面 {
        let 条件 = self.坂の場面の条件を組む();
        let 指定 = self.変更.組み立ての指定を作る(&条件, 適用規則);
        let mut 場面 = 坂の場面を指定で組む(&条件, &指定);
        self.変更.組んだ場面を計測の始点へ進める(&mut 場面);
        場面
    }

    /// この場合の許容差の適用規則(受理の倍率と右辺の δ の扱い)。
    pub(super) fn 許容差の適用規則(&self) -> 試験の許容差の適用規則 {
        試験の許容差の適用規則::倍率と行への適用規則から生成する(
            解けたと見なす許容差の倍率::比から生成する(self.許容差の比),
            self.行への適用規則,
        )
    }

    /// 表の見出し。本番と違う行への適用規則だけその印を添え、段階A1と同じ場合の見出しは段階A1と同じ綴りにする。
    pub(super) fn 見出し(&self) -> String {
        let 行への適用規則の印 = match self.行への適用規則 {
            接線の行への許容差の適用規則::全部の拘束行を追加し右辺に受理の倍率を掛けた許容差を残す => "",
            接線の行への許容差の適用規則::全部の拘束行を追加し右辺から許容差を外す => "_右辺δ零",
            接線の行への許容差の適用規則::許容差以下の接線変位の拘束行を追加しない => "_内側の行を積まず",
        };
        format!(
            "静止摩擦係数{}_正接{}_回し{}度_許容差{}倍{行への適用規則の印}{}",
            self.静止摩擦係数の値,
            self.傾きの正接,
            self.鉛直軸まわりの回しの度,
            self.許容差の比,
            self.変更.綴り()
        )
    }

    /// 計測の始点から指定の刻み数だけ本番の工程で進めた後の、坂に沿った変位と保持と滑走の分類。
    pub(super) fn 刻みを進めて分類する(&self, 刻み数: usize) -> 保持と滑走の分類 {
        let 条件 = self.坂の場面の条件を組む();
        let mut 場面 = self.場面を組む();
        let 初めの重心 = 場面.箱の配置.重心の位置();
        場面.細分を進める(刻み数 * self.変更.一刻みの細分数());
        保持と滑走の分類::場面の走行の結果から決める(
            場面.坂に沿った変位(初めの重心, &条件),
            場面.直前の細分の観測.滑走中の接触点の数,
            場面.粘着の候補が解けなかった接触点集合の延べ数,
            場面.錨を置き直した細分の延べ数,
        )
    }
}
