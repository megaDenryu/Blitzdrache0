//! 第一反復の入口の読み取りのうち、計測点1と2(擬似逆が捨てた固有の向きの採否と、捨てた向きの行空間での残差)を
//! 綴る工程(Issue #59の第4段階の許容差依存の診断)。1倍と2倍の内訳は同じ配置の同じ連立方程式から組んだため、勝った有効集合が
//! 同じなら行列も固有分解も同じであり、固有の向きを番号で対応させて採否を比べられる。有効集合が違えば対応しないと綴る。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の数値契約の診断_2026-09-06.md`

#![cfg(test)]

use super::entry_reading::第一反復の入口の読み取り;
use crate::contact::normal_tangential_system::単精度の解の内訳;
use crate::contact::symmetric_system::擬似逆が固有の向きを捨てた理由;

impl 第一反復の入口の読み取り {
    /// 計測点1と2(固有の向きごとの採否と、捨てた向きの行空間での残差)を綴る。
    pub(super) fn 計測点一と二を綴る(&self) {
        match (&self.一倍の内訳, &self.二倍の内訳) {
            (Some(一倍), Some(二倍)) => 二つの内訳を並べて綴る(一倍, 二倍),
            (一倍, 二倍) => println!("    B 内訳が定まらず 1倍={} 2倍={}", 一倍.is_some(), 二倍.is_some()),
        }
    }

    /// 1倍と2倍で採否が変わった固有の向きの番号。有効集合が違えば向きが対応しないため空である。
    pub(super) fn 採否が変わった向き(&self) -> Vec<usize> {
        match (&self.一倍の内訳, &self.二倍の内訳) {
            (Some(一倍), Some(二倍)) if 一倍.有効集合 == 二倍.有効集合 => 一倍
                .固有の向きごと
                .iter()
                .zip(二倍.固有の向きごと.iter())
                .enumerate()
                .filter(|(_, (前, 後))| 前.捨てた理由 != 後.捨てた理由)
                .map(|(k, _)| k)
                .collect(),
            _ => Vec::new(),
        }
    }
}

fn 二つの内訳を並べて綴る(一倍: &単精度の解の内訳, 二倍: &単精度の解の内訳) {
    println!(
        "    B 有効集合 1倍={} 2倍={} 行数={} 残差の最大 1倍={:.3e} 2倍={:.3e} 許容差の内側として捨てた向き 1倍={}本 2倍={}本 偽の固有値={}本",
        一倍.有効集合の綴り(),
        二倍.有効集合の綴り(),
        一倍.行ごとの残差.len(),
        一倍.行ごとの残差の最大(),
        二倍.行ごとの残差の最大(),
        一倍.捨てた向きの数(擬似逆が固有の向きを捨てた理由::右辺が許容差の内側),
        二倍.捨てた向きの数(擬似逆が固有の向きを捨てた理由::右辺が許容差の内側),
        一倍.捨てた向きの数(擬似逆が固有の向きを捨てた理由::偽の固有値)
    );
    for (k, (前, 後)) in 一倍.固有の向きごと.iter().zip(二倍.固有の向きごと.iter()).enumerate() {
        let 印 = if 前.捨てた理由 == 後.捨てた理由 {
            ""
        } else {
            " 採否変更"
        };
        println!(
            "    B 向き{k} λ={:.4e} vᵀb={:.4e} δ1倍={:.4e} δ2倍={:.4e} 採否1倍={:?} 採否2倍={:?} |β|={:.4e}{印}",
            前.固有値,
            前.右辺の射影,
            前.許容差の射影,
            後.許容差の射影,
            前.捨てた理由,
            後.捨てた理由,
            前.右辺の射影.abs()
        );
    }
    println!(
        "    B 行ごと 残差1倍={:?} 捨てた右辺1倍={:?} 許容差1倍={:?} 捨てた右辺2倍={:?}",
        小数で綴る(&一倍.行ごとの残差),
        小数で綴る(&一倍.行ごとの許容差の内側として捨てた右辺),
        小数で綴る(&一倍.行ごとの解けたと見なす許容差),
        小数で綴る(&二倍.行ごとの許容差の内側として捨てた右辺)
    );
}

fn 小数で綴る(並び: &[f32]) -> Vec<String> {
    並び.iter().map(|値| format!("{値:.3e}")).collect()
}
