//! 細分の終わりに接触点1つずつから読む量(Issue #103の段階A5の計測2)。錨からの接線変位の長さだけを並べる
//! `anchor_displacement`から分けているのは、あちらが1つの量の並びを返す工程であり、こちらが1つの接触点の
//! 素性(どの特徴どうしで生まれたか)と解の状態(乗数・錨を置き直したか・滑走中か)を1つに束ねた型だからである。
//! この束が要るのは、細分をまたいで交互に入れ替わる量が接触点の識別なのか乗数の配分なのかを分けるためである。
//! 入れ替わるのが識別なら原因の層は接触の候補と履歴であり、乗数の配分だけなら層は解法である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断16: 接触の履歴は参加者の組ごとに特徴の識別を鍵に全順序の併走で対応付け、暖機はしない」

#![cfg(test)]

use super::anchor_displacement::錨からの接線変位の長さの並び;
use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::feature_identity::接触の特徴の識別;
use crate::rigid_body::配置;

/// 細分の終わりに接触点1つから読んだ素性と解の状態。
pub(super) struct 接触点一つの細分の終わりの読み取り {
    特徴の識別: 接触の特徴の識別,
    錨からの接線変位の長さ: f64,
    接線のラグランジュ乗数の大きさ: f32,
    法線のラグランジュ乗数: f32,
    錨を置き直したか: bool,
    滑走中か: bool,
}

impl 接触点一つの細分の終わりの読み取り {
    /// 表へ綴る形。
    pub(super) fn 綴り(&self) -> String {
        format!(
            "特徴={:?} |C_t|={:.4e} λ_t={:.4e} λ_n={:.4e} 置き直した={} 滑走中={}",
            self.特徴の識別,
            self.錨からの接線変位の長さ,
            self.接線のラグランジュ乗数の大きさ,
            self.法線のラグランジュ乗数,
            self.錨を置き直したか,
            self.滑走中か
        )
    }

    /// この接触点の特徴の識別。細分をまたいで並びが入れ替わったかを数える計器が比べる。
    pub(super) fn 特徴の識別(&self) -> 接触の特徴の識別 {
        self.特徴の識別
    }

    pub(super) fn 錨を置き直したか(&self) -> bool {
        self.錨を置き直したか
    }

    pub(super) fn 滑走中か(&self) -> bool {
        self.滑走中か
    }
}

/// 接触点ごとの細分の終わりの読み取り。並びは接触点集合の点の番号と同じである。
pub(super) fn 接触点ごとの細分の終わりを読む(
    接触点集合: &[剛体と静的世界の接触拘束],
    配置: &配置,
) -> Vec<接触点一つの細分の終わりの読み取り> {
    let 接線変位 = 錨からの接線変位の長さの並び(接触点集合, 配置);
    接触点集合
        .iter()
        .zip(接線変位)
        .map(|(拘束, 長さ)| {
            let 状態 = 拘束.静止摩擦の解の状態();
            接触点一つの細分の終わりの読み取り {
                特徴の識別: 拘束.引数().特徴の識別,
                錨からの接線変位の長さ: 長さ,
                接線のラグランジュ乗数の大きさ: 状態.接線のラグランジュ乗数().大きさ().値(),
                法線のラグランジュ乗数: 拘束.法線のラグランジュ乗数().値(),
                錨を置き直したか: 状態.錨を置き直したか(),
                滑走中か: 状態.滑走中か(),
            }
        })
        .collect()
}
