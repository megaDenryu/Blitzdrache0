//! 位置の反復1回を終えた直後にバッチと配置から読む量(Issue #59の第4段階の許容差依存の診断。計測点5の増幅器)。
//! 持つのは、確定した法線の乗数の合計 Σλ_n・確定した接線の乗数の合力の大きさ ‖Σλ_t‖・滑走中の点の数・粘着の候補が
//! 解けなかった集合の数・その配置での錨からの接線変位の合計の5つである。円錐の比 ‖Σλ_t‖÷Σλ_n をこの型が答える。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::anchor_displacement::{合計を求める, 錨からの接線変位の長さの並び};
use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::static_friction::接線のラグランジュ乗数;
use crate::rigid_body::配置;
use crate::xpbd::ラグランジュ乗数;

/// 反復1回を終えた直後の読み取り。
pub(super) struct 反復の後の読み取り {
    pub(super) 法線の乗数の合計: f64,
    pub(super) 接線の合力の大きさ: f64,
    pub(super) 滑走中の点の数: usize,
    pub(super) 解けなかった集合の数: usize,
    pub(super) 錨からの接線変位の合計: f64,
}

impl 反復の後の読み取り {
    pub(super) fn 接触点集合と配置から読む(
        接触点集合: &[剛体と静的世界の接触拘束], 配置: &配置, 解けなかった集合の数: usize
    ) -> Self {
        let 法線 = 接触点集合
            .iter()
            .fold(ラグランジュ乗数::零(), |合計, 拘束| 合計 + 拘束.法線のラグランジュ乗数());
        let 接線 = 接触点集合.iter().fold(接線のラグランジュ乗数::零(), |合計, 拘束| {
            合計 + 拘束.静止摩擦の解の状態().接線のラグランジュ乗数()
        });
        Self {
            法線の乗数の合計: f64::from(法線.値()),
            接線の合力の大きさ: f64::from(接線.大きさ().値()),
            滑走中の点の数: 接触点集合.iter().filter(|拘束| 拘束.静止摩擦の解の状態().滑走中か()).count(),
            解けなかった集合の数,
            錨からの接線変位の合計: 合計を求める(&錨からの接線変位の長さの並び(接触点集合, 配置)),
        }
    }

    /// 円錐の比 ‖Σλ_t‖ ÷ Σλ_n。静止摩擦係数と直に比べる量である。法線の乗数が零なら零である。
    pub(super) fn 円錐の比(&self) -> f64 {
        if self.法線の乗数の合計 > 0.0 {
            self.接線の合力の大きさ / self.法線の乗数の合計
        } else {
            0.0
        }
    }
}
