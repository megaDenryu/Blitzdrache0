//! 細分1本の記録を表の行として綴る工程(Issue #59の第4段階の許容差依存の診断)。記録の型(`substep_record`)から
//! 分けているのは、こちらが表の書式を持ち、あちらが値を持つからである。綴りは2つである。計測点0と5の1行と、
//! 計測点3の倍精度の3由来と解析の期待の1行である。計測点1と2の固有の向きごとの行は`direction_line`が綴る。合否は判定しない。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の数値契約の診断_2026-09-06.md`

#![cfg(test)]

use super::entry_reading::第一反復の入口の読み取り;
use super::substep_record::許容差依存の細分の記録;

impl 許容差依存の細分の記録 {
    /// 計測点0(細分の終わりの接線変位と速さ)と計測点5(反復ごとの比と作り直しの割合)を1行に綴る。
    pub(super) fn 計測点零と五を綴る(&self, 刻み幅の秒: f64) {
        let 反復ごと: Vec<String> = self
            .反復ごと
            .iter()
            .enumerate()
            .map(|(番号, 反復)| {
                format!(
                    "反復{番号}後 比={:.6} Σλ_n={:.4e} Σ|Δt|={:.4e} 滑走{} 解けず{}(精度不足{})",
                    反復.円錐の比(),
                    反復.法線の乗数の合計,
                    反復.錨からの接線変位の合計,
                    反復.滑走中の点の数,
                    反復.解けなかった集合の数,
                    反復.表現の精度が不足した集合の数
                )
            })
            .collect();
        println!(
            "  細分{} 入口Σ|Δt|={:.4e} | {} | 終わりΣ|Δt|={:.4e} 点ごと={:?} 作り直し割合={:.4} v↓={:.4e} v↓h/δt={:.4} δt={:.4e}",
            self.番号,
            self.入口の接線変位の合計,
            反復ごと.join(" | "),
            self.終わりの接線変位の合計(),
            self.終わりの接線変位.iter().map(|値| format!("{値:.3e}")).collect::<Vec<_>>(),
            self.反復零の後に接線変位が作り直された割合(),
            self.下り向きの速さ,
            self.速さの一細分の変位と許容差の比(刻み幅の秒),
            self.接線の行の許容差,
        );
    }
}

impl 第一反復の入口の読み取り {
    /// 計測点3(倍精度の3由来と解析の期待)と単精度の1倍・2倍を1行に綴る。解析の期待は「円錐の内側」である。
    pub(super) fn 計測点三を綴る(&self) {
        println!(
            "    C 単精度1倍={} 単精度2倍={} 倍精度の刻み={} (行の残差の最大={}) 実測の下限={} 据え置き={} 解析=内側 不一致=[{}]",
            self.単精度の一倍.結末と判定の綴り(),
            self.単精度の二倍.結末と判定の綴り(),
            self.倍精度の刻み.結末と判定の綴り(),
            self.倍精度の刻みの行ごとの残差の最大
                .map_or("定まらず".to_owned(), |値| format!("{値:.3e}")),
            self.実測の残差の下限.結末と判定の綴り(),
            self.単精度の許容差を据え置いた倍精度.結末と判定の綴り(),
            self.解析と一致しない列().join(","),
        );
    }

    /// 解析の期待(円錐の内側)と一致しない列の名前。定まらなかった結末も不一致に数える。
    pub(super) fn 解析と一致しない列(&self) -> Vec<&'static str> {
        [
            ("単精度1倍", &self.単精度の一倍),
            ("単精度2倍", &self.単精度の二倍),
            ("倍精度の刻み", &self.倍精度の刻み),
            ("実測の下限", &self.実測の残差の下限),
            ("据え置き", &self.単精度の許容差を据え置いた倍精度),
        ]
        .into_iter()
        .filter(|(_, 読み取り)| !(読み取り.円錐の内側か() && 読み取り.結末の綴り() == "定まった"))
        .map(|(名前, _)| 名前)
        .collect()
    }
}
