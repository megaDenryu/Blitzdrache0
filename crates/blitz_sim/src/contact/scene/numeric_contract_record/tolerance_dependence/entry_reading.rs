//! 細分の第一反復の入口(予測と履歴の併走の後、補正を1度も適用していない配置)で読む量(Issue #59の第4段階の
//! 許容差依存の診断。計測点1・2・3)。同じ配置の同じ接触点集合へ、単精度で許容差の倍率1倍と2倍を当てた読み取りと
//! その解の内訳、倍精度の参照を3つの由来(倍精度の刻み・実測の残差の下限・単精度の許容差の据え置き)で解いた読み取り、
//! を持つ。単精度の2倍を軌道でなく同じ配置に当てるのは、軌道の差を採否の差へ混ぜないためである。
//! 1倍の接線の行の許容差 δ_t を読む口も持つ。こちらは倍精度の求解を伴わず安いため、2倍の軌道の細分も毎細分読む。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の数値契約の診断_2026-09-06.md`

#![cfg(test)]

use super::super::candidate_reading::粘着の候補の読み取り;
use super::実測の残差の下限メートル;
use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::normal_tangential_system::{
    単精度の解の内訳, 参照計算の許容差の由来, 解けたと見なす許容差の倍率
};
use crate::contact::scene::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_body::配置;
use crate::rigid_xpbd::姿勢自由度の参加者;

/// 第一反復の入口の読み取り。
pub(super) struct 第一反復の入口の読み取り {
    pub(super) 単精度の一倍: 粘着の候補の読み取り,
    pub(super) 単精度の二倍: 粘着の候補の読み取り,
    pub(super) 一倍の内訳: Option<単精度の解の内訳>,
    pub(super) 二倍の内訳: Option<単精度の解の内訳>,
    pub(super) 倍精度の刻み: 粘着の候補の読み取り,
    pub(super) 倍精度の刻みの行ごとの残差の最大: Option<f64>,
    pub(super) 実測の残差の下限: 粘着の候補の読み取り,
    pub(super) 単精度の許容差を据え置いた倍精度: 粘着の候補の読み取り,
}

impl 一つの箱と静的な直方体の場面 {
    /// 第一反復の入口を読む。状態は書き換えない。
    pub(super) fn 第一反復の入口を読む(
        &self,
        接触点集合: &[剛体と静的世界の接触拘束],
        配置: &配置,
    ) -> 第一反復の入口の読み取り {
        let 参加者 = 姿勢自由度の参加者::動的(*配置, &self.箱の質量特性);
        let 一倍 = self
            .試験の許容差の当て方
            .受理の倍率を差し替える(解けたと見なす許容差の倍率::既定で生成する());
        let 二倍 = self
            .試験の許容差の当て方
            .受理の倍率を差し替える(解けたと見なす許容差の倍率::比から生成する(2.0));
        let (連立の一倍, _) = self.法線と接線の連立を許容差の当て方で組む(接触点集合, &参加者, 一倍);
        let (連立の二倍, _) = self.法線と接線の連立を許容差の当て方で組む(接触点集合, &参加者, 二倍);
        let (倍精度の刻み, 内訳) = self.倍精度で粘着の候補を読む(接触点集合, 配置, 参照計算の許容差の由来::倍精度の表現の刻みから導く);
        let (実測の残差の下限, _) = self.倍精度で粘着の候補を読む(
            接触点集合,
            配置,
            参照計算の許容差の由来::実測の残差の下限を据える {
                下限: 実測の残差の下限メートル,
            },
        );
        let (据え置き, _) = self.倍精度で粘着の候補を読む(接触点集合, 配置, 参照計算の許容差の由来::単精度の許容差を据え置く);
        第一反復の入口の読み取り {
            単精度の一倍: self.単精度で許容差の当て方を当てて粘着の候補を読む(接触点集合, &参加者, 一倍),
            単精度の二倍: self.単精度で許容差の当て方を当てて粘着の候補を読む(接触点集合, &参加者, 二倍),
            一倍の内訳: 連立の一倍.定まった解の内訳を読む(),
            二倍の内訳: 連立の二倍.定まった解の内訳を読む(),
            倍精度の刻み,
            倍精度の刻みの行ごとの残差の最大: 内訳.map(|内訳| 内訳.行ごとの残差の最大()),
            実測の残差の下限,
            単精度の許容差を据え置いた倍精度: 据え置き,
        }
    }

    /// 1倍の接線の行が持つ解けたと見なす許容差 δ_t(メートル)。接線の行を1つも積めない配置では零である。
    pub(super) fn 接線の行の許容差を読む(&self, 接触点集合: &[剛体と静的世界の接触拘束], 配置: &配置) -> f64 {
        let 参加者 = 姿勢自由度の参加者::動的(*配置, &self.箱の質量特性);
        let (連立, _) = self.法線と接線の連立を許容差の当て方で組む(接触点集合, &参加者, self.試験の許容差の当て方);
        (0..連立.点の数())
            .find_map(|番号| 連立.接線の一行を読む(番号))
            .map_or(0.0, |一行| f64::from(一行.勾配().解けたと見なす許容差().値()))
    }
}
