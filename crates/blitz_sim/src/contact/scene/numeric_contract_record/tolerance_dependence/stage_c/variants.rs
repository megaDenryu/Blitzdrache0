const 閾値の帯の倍率: f32 = 4.0;

fn 本番の場合(
    傾きの正接: f32, 鉛直軸まわりの回しの度: f32, 変更: 段階A1の場面からの一つの変更
) -> 許容差依存の診断の場合 {
    許容差依存の診断の場合 {
        静止摩擦係数の値: 0.6,
        傾きの正接,
        鉛直軸まわりの回しの度,
        許容差の比: 1.0,
        行への適用規則: 接線の行への許容差の適用規則::許容差以下の接線変位の拘束行を追加しない,
        変更,
    }
}

fn 受理の判定だけへ届く適用規則(倍率: f32) -> 試験の許容差の適用規則 {
    試験の許容差の適用規則::本番と同じ適用規則()
        .受理の倍率を差し替える(解けたと見なす許容差の倍率::比から生成する(倍率))
        .届く先を差し替える(受理の倍率の届く先::受理の判定だけ)
}

fn 閾値の帯の適用規則() -> 試験の許容差の適用規則 {
    試験の許容差の適用規則::本番と同じ適用規則().行を積む閾値の倍率を差し替える(行を積む閾値の倍率::比から生成する(閾値の帯の倍率))
}

fn 遠方の移動() -> 段階A1の場面からの一つの変更 {
    段階A1の場面からの一つの変更::坂の面の法線の向きへ動かす {
        長さ: メートル::生成する(刻みを二倍にする長さ),
    }
}

