//! 段階Cの検収で並べる組(段階Cの計器)。27組の行列・細分16本の完了条件とその旧の形の対照・刻み2倍の平行移動と
//! 正接0.58の敵対の反例を、それぞれ1つの計器として置く。走行と読み取りは `classification` が持つ。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

use blitz_math::メートル;

use super::super::case::許容差依存の診断の場合;
use super::super::row_admission::刻みを二倍にする長さ;
use super::super::scene_variation::段階A1の場面からの一つの変更;
use super::classification::分類と退避を綴る;
use crate::contact::normal_tangential_system::接線の行への許容差の当て方;

const 静止摩擦係数の値: f32 = 0.6;
const 行列の正接: &[f32] = &[0.50, 0.55, 0.61];
const 行列の回しの度: &[f32] = &[0.0, 30.0, 45.0];
const 振る受理の倍率: &[f32] = &[0.5, 1.0, 2.0];
const 敵対の傾きの正接: f32 = 0.58;

fn 本番の場合(
    傾きの正接: f32,
    鉛直軸まわりの回しの度: f32,
    許容差の比: f32,
    変更: 段階A1の場面からの一つの変更,
) -> 許容差依存の診断の場合 {
    許容差依存の診断の場合 {
        静止摩擦係数の値,
        傾きの正接,
        鉛直軸まわりの回しの度,
        許容差の比,
        行への許容差の当て方: 接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする,
        変更,
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 本実装の検収_二十七組を本番の当て方で綴る() {
    for &倍率 in 振る受理の倍率 {
        for &回し in 行列の回しの度 {
            for &正接 in 行列の正接 {
                分類と退避を綴る(&本番の場合(正接, 回し, 倍率, 段階A1の場面からの一つの変更::無し));
            }
        }
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 本実装の検収_細分十六本の正接零点五五を三方向と旧の形で綴る() {
    for &回し in 行列の回しの度 {
        分類と退避を綴る(&本番の場合(0.55, 回し, 1.0, 段階A1の場面からの一つの変更::細分数を十六にする));
    }
    let 旧の形 = 許容差依存の診断の場合 {
        行への許容差の当て方: 接線の行への許容差の当て方::右辺へ受理の倍率を掛けて残す,
        ..本番の場合(0.55, 0.0, 1.0, 段階A1の場面からの一つの変更::細分数を十六にする)
    };
    分類と退避を綴る(&旧の形);
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 本実装の検収_刻み二倍の平行移動と正接零点五八を本番と候補一で綴る() {
    let 移動 = 段階A1の場面からの一つの変更::坂の面の法線の向きへ動かす {
        長さ: メートル::生成する(刻みを二倍にする長さ),
    };
    for &倍率 in 振る受理の倍率 {
        分類と退避を綴る(&本番の場合(敵対の傾きの正接, 0.0, 倍率, 移動));
    }
    let 候補一 = 許容差依存の診断の場合 {
        行への許容差の当て方: 接線の行への許容差の当て方::右辺を零にする,
        ..本番の場合(敵対の傾きの正接, 0.0, 1.0, 移動)
    };
    分類と退避を綴る(&候補一);
}
