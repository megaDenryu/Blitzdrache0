fn 落ちた場面の細分_遠方の正接零点五八を受理の倍率ごとに綴る() {
    let 移動 = 段階A1の場面からの一つの変更::坂の面の法線の向きへ動かす {
        長さ: メートル::生成する(刻みを二倍にする長さ),
    };
    for 倍率 in [1.0, 2.0] {
        細分ごとに退避を綴る(&本番の場合(0.58, 倍率, 移動));
    }
}

