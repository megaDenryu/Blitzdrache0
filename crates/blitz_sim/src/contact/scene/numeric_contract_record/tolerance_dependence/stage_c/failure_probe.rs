//! 段階Cの検収で落ちた坂の2場面(遠方の正接0.58・受理2倍、許容差の境界の正接0.48〜0.52・受理1倍)を細分ごとに読む計器
//! (親の指示による診断)。細分ごとに、退避へ落ちた反復の番号と結末(受理の判定が破れたなら契約の名前と残差と許容差の比と
//! 積まれていた接線の行の C_t/δ)を綴り、最初に滑走中と印された細分と、600刻みの結末ごとの延べ数を綴る。合否は判定しない。
//! 実行は `cargo test -p blitz_sim --release 落ちた場面の細分 -- --ignored --nocapture` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

use std::collections::BTreeMap;

use blitz_math::メートル;

use super::super::case::許容差依存の診断の場合;
use super::super::row_admission::刻みを二倍にする長さ;
use super::super::scene_variation::段階A1の場面からの一つの変更;
use crate::contact::normal_tangential_system::接線の行への許容差の当て方;

const 分類を見る刻み数: usize = 600;
const 細分ごとに綴る本数: usize = 64;
const 綴る件数の上限: usize = 40;

fn 本番の場合(
    傾きの正接: f32, 許容差の比: f32, 変更: 段階A1の場面からの一つの変更
) -> 許容差依存の診断の場合 {
    許容差依存の診断の場合 {
        静止摩擦係数の値: 0.6,
        傾きの正接,
        鉛直軸まわりの回しの度: 0.0,
        許容差の比,
        行への許容差の当て方: 接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする,
        変更,
    }
}

// 1組を600刻み走らせ、細分ごとの退避の反復と結末を綴り、結末ごとの延べ数と最初に滑走した細分を綴る。
fn 細分ごとに退避を綴る(場合: &許容差依存の診断の場合) {
    let 条件 = 場合.坂の場面の条件を組む();
    let 本数 = 分類を見る刻み数 * 場合.変更.一刻みの細分数();
    let mut 場面 = 場合.場面を組む();
    let 初めの重心 = 場面.箱の配置.重心の位置();
    let mut 結末ごと: BTreeMap<&'static str, usize> = BTreeMap::new();
    let (mut 綴った件数, mut 最初に滑走した細分) = (0, None);
    println!(
        "[{}] 細分ごとの退避(最初の{細分ごとに綴る本数}細分は全件、以後は{綴る件数の上限}件まで)",
        場合.見出し()
    );
    for 番号 in 0..本数 {
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, false);
        if 最初に滑走した細分.is_none() && 記録.滑走中か() {
            最初に滑走した細分 = Some(番号);
            println!(
                "  細分{番号}: 円錐を超えて滑走中と印された(反復ごとの比={:?})",
                記録.反復ごと.iter().map(|反復| 反復.円錐の比()).collect::<Vec<_>>()
            );
        }
        for (反復, 読み取り) in &記録.解けなかった連立 {
            *結末ごと.entry(読み取り.結末の綴り).or_insert(0) += 1;
            if 番号 < 細分ごとに綴る本数 || 綴った件数 < 綴る件数の上限 {
                綴った件数 += usize::from(番号 >= 細分ごとに綴る本数);
                println!("  細分{番号} 反復{反復} {}", 読み取り.綴り());
            }
        }
    }
    let 変位 = 場面.坂に沿った変位(初めの重心, &条件);
    let 内訳: Vec<String> = 結末ごと.iter().map(|(結末, 数)| format!("{結末}={数}")).collect();
    println!(
        "  要約 変位={変位:.3e} 最初に滑走した細分={最初に滑走した細分:?} 退避の内訳[{}]",
        内訳.join(" ")
    );
}

