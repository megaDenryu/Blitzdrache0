//! 1組を600刻み走らせ、分類と退避の件数と理由の内訳を綴る工程(段階Cの計器)。行列を並べる側(`matrix`)から分けているのは、
//! こちらが1組の走行と読み取りであり、あちらがどの組を並べるかを決める側だからである。
//! 退避の理由は、反復ごとの解けなかった連立の読み取りの結末の綴りを鍵に数える。同じ細分の2つの反復で退避が起きれば2件と数える。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

use std::collections::BTreeMap;

use super::super::case::許容差依存の診断の場合;
use crate::contact::normal_tangential_system::試験の許容差の適用規則;

const 分類を見る刻み数: usize = 600;

/// 1組の走行から読んだ、退避の理由ごとの延べ数。
pub(super) struct 退避の理由の内訳 {
    理由ごとの延べ数: BTreeMap<&'static str, usize>,
}

impl 退避の理由の内訳 {
    fn 零から始める() -> Self {
        Self {
            理由ごとの延べ数: BTreeMap::new(),
        }
    }

    fn 一件を数える(&mut self, 結末の綴り: &'static str) {
        *self.理由ごとの延べ数.entry(結末の綴り).or_insert(0) += 1;
    }

    fn 延べ数(&self) -> usize {
        self.理由ごとの延べ数.values().sum()
    }

    fn 綴り(&self) -> String {
        let 内訳: Vec<String> = self.理由ごとの延べ数.iter().map(|(理由, 数)| format!("{理由}={数}")).collect();
        format!("退避{}[{}]", self.延べ数(), 内訳.join(" "))
    }
}

/// 1組を600刻み走らせ、分類・坂に沿った変位・退避の件数と理由・錨の置き直しの延べ数を1行に綴る。
pub(super) fn 分類と退避を綴る(場合: &許容差依存の診断の場合) {
    分類と退避を適用規則で綴る(場合, 場合.許容差の適用規則());
}

/// 同じ組を、指定の許容差の適用規則(届く先や閾値の倍率を振ったもの)で走らせて綴る。見出しは適用規則の綴りを使う。
pub(super) fn 分類と退避を適用規則で綴る(場合: &許容差依存の診断の場合, 適用規則: 試験の許容差の適用規則) {
    let 条件 = 場合.坂の場面の条件を組む();
    let 本数 = 分類を見る刻み数 * 場合.変更.一刻みの細分数();
    let mut 場面 = 場合.場面を適用規則で組む(適用規則);
    let 初めの重心 = 場面.箱の配置.重心の位置();
    let mut 内訳 = 退避の理由の内訳::零から始める();
    for 番号 in 0..本数 {
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, false);
        for (_, 読み取り) in &記録.解けなかった連立 {
            内訳.一件を数える(読み取り.結末の綴り);
        }
    }
    let 変位 = 場面.坂に沿った変位(初めの重心, &条件);
    let 滑走中 = 場面.直前の細分の観測.滑走中の接触点の数;
    let 分類 = if 変位.abs() <= 1.0e-3 && 滑走中 == 0 { "保持" } else { "滑走" };
    println!(
        "  分類 [{}_{}] {分類を見る刻み数}刻み {分類} 変位={変位:.3e} {} 置き直し{}",
        場合.見出し(),
        適用規則.綴り(),
        内訳.綴り(),
        場面.錨を置き直した細分の延べ数
    );
}
