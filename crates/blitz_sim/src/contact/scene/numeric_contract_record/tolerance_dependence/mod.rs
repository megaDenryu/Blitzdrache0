// 並べる細分の本数。8細分が基本刻み1本であり、64本は8刻みに当たる(第1段階の表6と同じ範囲)。
pub(super) const 並べる細分の本数: usize = 64;
// 倍精度の参照の由来(b)が全部の行へ据える許容差。第1段階の観測4が測った、倍精度でも残る行の残差の下限の上端である。
pub(super) const 実測の残差の下限メートル: f64 = 6.0e-8;
const 分類を見る刻み数: usize = 600;
const 細分の刻み幅の秒: f64 = 1.0 / 480.0;
const 傾きの正接: f32 = 0.55;
const 鉛直軸まわりの回しの度: f32 = 0.0;

fn 場合を組む(静止摩擦係数の値: f32, 許容差の比: f32) -> 許容差依存の診断の場合 {
    許容差依存の診断の場合 {
        静止摩擦係数の値,
        傾きの正接,
        鉛直軸まわりの回しの度,
        許容差の比,
        行への許容差の当て方: 接線の行への許容差の当て方::右辺へ受理の倍率を掛けて残す,
        変更: 段階A1の場面からの一つの変更::無し,
    }
}

// 1本の軌道を64細分進めながら記録を綴る。入口を読むかは1倍の軌道だけ真にする(計測点1〜3は同じ配置に両倍率を当てる)。
fn 一本の軌道を綴る(場合: &許容差依存の診断の場合, 入口を読むか: bool) -> Vec<許容差依存の細分の記録> {
    let 条件 = 場合.坂の場面の条件を組む();
    let mut 場面 = 場合.場面を組む();
    println!("[{}] 細分0〜{}", 場合.見出し(), 並べる細分の本数 - 1);
    (0..並べる細分の本数)
        .map(|番号| {
            let 記録 = 場面.記録しながら一細分進める(番号, &条件, 入口を読むか);
            記録.計測点零と五を綴る(細分の刻み幅の秒);
            if let Some(入口) = &記録.入口 {
                入口.計測点三を綴る();
                入口.計測点一と二を綴る();
            }
            記録
        })
        .collect()
}

fn 分類を綴る(静止摩擦係数の値: f32) {
    for 許容差の比 in [1.0, 2.0] {
        let 場合 = 場合を組む(静止摩擦係数の値, 許容差の比);
        let 分類 = 場合.刻みを進めて分類する(分類を見る刻み数);
        println!(
            "  分類 [{}] {分類を見る刻み数}刻み {} 変位={:.3e} 解けず{} 置き直し{}",
            場合.見出し(),
            分類.綴り(),
            分類.坂に沿った変位(),
            分類.粘着の候補が解けなかった延べ数(),
            分類.錨を置き直した細分の延べ数()
        );
    }
}

fn 一つの静止摩擦係数を綴る(静止摩擦係数の値: f32, 入口を読むか: bool) {
    let 記録 = 二つの軌道の記録 {
        一倍: 一本の軌道を綴る(&場合を組む(静止摩擦係数の値, 1.0), 入口を読むか),
        二倍: 一本の軌道を綴る(&場合を組む(静止摩擦係数の値, 2.0), false),
    };
    記録.要約を綴る(f64::from(静止摩擦係数の値));
    分類を綴る(静止摩擦係数の値);
}

