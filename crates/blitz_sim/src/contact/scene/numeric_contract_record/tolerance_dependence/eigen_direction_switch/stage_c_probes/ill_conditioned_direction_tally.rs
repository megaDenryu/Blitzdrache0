//! Issue #103の段階Cの第2手の計器が溜める「条件の悪い向き」の集まり(親の2026-09-13の指示)。
//! 9600細分の全部の向きを1行ずつ綴ると読めない量になるため、この型が延べ本数・現れた細分の番号・剛体へ入る並進の
//! 分布・同じ細分でいちばん強い向きの並進に対する比へ畳む。読み取り1本ずつの行は、先頭の何本かだけを綴る。
//! 現れた細分の数を別に持たないのは、番号の並びが細分ごとに1つだけ入るためであり、数は並びの長さで答える。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::ill_conditioned_direction_reading::条件の悪い向き一本の読み取り;

// 読み取り1本ずつの行を綴る上限。親の指示の「先頭20件まで」である。
const 一本ずつ綴る上限: usize = 20;

/// 条件の悪い向きの集まり。
pub(super) struct 条件の悪い向きの集まり {
    延べ本数: usize,
    剛体へ入る並進の並び: Vec<f64>,
    最も強い向きの並進への比の並び: Vec<f64>,
    現れた細分の番号: Vec<usize>,
}

impl 条件の悪い向きの集まり {
    pub(super) fn 零から始める() -> Self {
        Self {
            延べ本数: 0,
            剛体へ入る並進の並び: Vec::new(),
            最も強い向きの並進への比の並び: Vec::new(),
            現れた細分の番号: Vec::new(),
        }
    }

    /// 1本を数える。同じ細分から2本目が来ても細分の番号は増やさない。先頭の何本かは読み取りの行も綴る。
    pub(super) fn 一本を数える(&mut self, 読み取り: &条件の悪い向き一本の読み取り) {
        if self.延べ本数 < 一本ずつ綴る上限 {
            println!("    W {}", 読み取り.綴り());
        }
        self.延べ本数 += 1;
        self.剛体へ入る並進の並び.push(読み取り.剛体へ入る並進);
        self.最も強い向きの並進への比の並び.push(読み取り.最も強い向きの並進への比());
        if self.現れた細分の番号.last() != Some(&読み取り.細分の番号) {
            self.現れた細分の番号.push(読み取り.細分の番号);
        }
    }

    /// 表へ綴る形。
    pub(super) fn 綴り(&self) -> String {
        format!(
            "現れた細分={}個 延べ本数={}本 並進[{}] 最も強い向きの並進への比[{}]",
            self.現れた細分の番号.len(),
            self.延べ本数,
            最大と中央と最小の綴り(&self.剛体へ入る並進の並び),
            最大と中央と最小の綴り(&self.最も強い向きの並進への比の並び)
        )
    }

    /// 現れた細分の番号を先頭から指定の件数まで綴った形。
    pub(super) fn 現れた細分の番号の綴り(&self) -> String {
        let 先頭: Vec<String> = self.現れた細分の番号.iter().take(一本ずつ綴る上限).map(usize::to_string).collect();
        format!("先頭{}件={}", 先頭.len(), 先頭.join(","))
    }
}

// 並びの最大・中央・最小を綴る。空なら「観測無し」である。
fn 最大と中央と最小の綴り(並び: &[f64]) -> String {
    if 並び.is_empty() {
        return "観測無し".to_owned();
    }
    let mut 小さい順 = 並び.to_vec();
    小さい順.sort_by(f64::total_cmp);
    let 中央 = 小さい順[小さい順.len() / 2];
    format!("最大={:.4e} 中央={中央:.4e} 最小={:.4e}", 小さい順[小さい順.len() - 1], 小さい順[0])
}
