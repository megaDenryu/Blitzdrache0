//! Issue #103の段階A6の追補の計器。細分16本の正接0.55の坂を4つの規則で進め、**滑走するより前の細分だけ**の
//! 円錐の比 ‖Σλ_t‖ ÷ Σλ_n の振れを綴る(親の2026-09-12の指示)。
//! これが要るのは、`first_cone_crossing`が測った「滑走した細分の手前3本の比」が 0.5434 から 0.5577 に居て、
//! 静止摩擦係数0.6までの余裕が8パーセントしか無いことが分かった一方で、**本番の比の振れが枝より小さいか**を
//! 測っていないためである。振れが小さいなら、右辺の判定が捨てることは比の振れを抑えていることになる。
//! 本番はこの3方向で1本も滑走しないため、上限の細分の本数で打ち切る。枝は滑走した細分の1つ手前まで数える。
//! 打ち切りの本数を置くのは、本番だけ9600細分を数えると、比べる細分の本数が枝と2桁違うためである。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 滑走の前の円錐の比 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::alternative_discard_record::{三つの捨て方, 捨て方を当てた適用規則};
use super::cone_ratio_spread::円錐の比の振れ;
use super::first_cone_crossing::{傾きの正接, 振る回しの度, 細分十六本の場合, 走らせる刻みの数};
use crate::contact::normal_tangential_system::試験の許容差の当て方;

// 本番が滑走しないときに数えるのをやめる細分の本数。
const 数える細分の上限: usize = 64;

// 滑走するより前の細分の比を数えて綴る。滑走した細分の番号も返す。
fn 一つの適用規則の比の振れを綴る(見出し: &str, 回しの度: f32, 適用規則: 試験の許容差の当て方) {
    let 場合 = 細分十六本の場合(回しの度);
    let 条件 = 場合.坂の場面の条件を組む();
    let 本数 = (走らせる刻みの数 * 場合.変更.一刻みの細分数()).min(数える細分の上限);
    let mut 場面 = 場合.場面を当て方で組む(適用規則);
    let mut 振れ = 円錐の比の振れ::零から始める();
    let mut 滑走した細分 = None;
    for 番号 in 0..本数 {
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, false);
        if 記録.滑走中か() {
            滑走した細分 = Some(番号);
            break;
        }
        if 番号 > 0 {
            振れ.一細分の比を数える(記録.最後の反復の後の円錐の比());
        }
    }
    println!(
        "  Z [回し{回しの度}度_{見出し}] 正接{傾きの正接} 滑走した細分={滑走した細分:?} {}",
        振れ.綴り()
    );
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 滑走の前の円錐の比_細分十六本の正接零点五五を四つの規則で綴る() {
    for &回しの度 in 振る回しの度 {
        一つの適用規則の比の振れを綴る("本番の適用規則", 回しの度, 試験の許容差の当て方::本番と同じ当て方());
        for 捨て方 in 三つの捨て方() {
            一つの適用規則の比の振れを綴る(&捨て方.綴り(), 回しの度, 捨て方を当てた適用規則(捨て方));
        }
    }
}
