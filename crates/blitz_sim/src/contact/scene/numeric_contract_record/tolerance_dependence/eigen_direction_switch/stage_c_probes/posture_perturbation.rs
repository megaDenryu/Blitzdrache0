//! Issue #103の段階Cの第1手の計器が使う、場面を組んだ後に箱の姿勢をほんの少し回す口(親の2026-09-13の指示)。
//! この口を呼ぶのは対照の走行を組む計器だけであり、本番の経路はどの細分でもこの口を呼ばない。
//! 回す角は、段階Bの表90が測った「代わりの捨て方が回し0度の細分0で剛体へ入れた回転 1.8531e-11 ラジアン」に揃える。
//! 注意: 姿勢は単精度の単位四元数である。大きさが1に近い成分へこの角の半分(9.3e-12)を足しても、単精度の刻み
//! (1のとき 1.2e-7)に負けて丸めで消える。消えたか残ったかを呼び出し側が読めるよう、この口は回す前と回した後の
//! 配置を突き合わせた結果を返す。零の成分へ足した増分だけが残るため、届くかどうかは姿勢によって変わる。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use blitz_math::{ラジアン, ワールド, 回転ベクトル};

use crate::contact::scene::substep_harness::一つの箱と静的な直方体の場面;

/// 段階Bの表90の、代わりの捨て方が回し0度の細分0で剛体へ入れた回転。
pub(super) const 摂動の角のラジアン: f32 = 1.8531e-11;
/// 回す軸。段階Bは向きごとの回転の軸を綴っていないため、固定した軸を選んだ。
pub(super) const 摂動を回す軸の綴り: &str = "ワールドの鉛直軸(+y)";

/// 摂動が単精度の姿勢を動かしたか。
pub(super) enum 摂動が姿勢を動かしたか {
    動かした,
    丸めで消えた,
}

impl 摂動が姿勢を動かしたか {
    pub(super) fn 綴り(&self) -> &'static str {
        match self {
            Self::動かした => "摂動が姿勢を動かした",
            Self::丸めで消えた => "摂動が単精度の丸めで消えた(配置が1ビットも動いていない)",
        }
    }
}

/// 箱の姿勢を摂動の角だけ回し、単精度の配置が動いたかを返す。
pub(super) fn 箱の姿勢を摂動で回す(場面: &mut 一つの箱と静的な直方体の場面) -> 摂動が姿勢を動かしたか {
    let 回す前の配置 = 場面.箱の配置;
    let 摂動 = 回転ベクトル::<ワールド>::成分から生成する(
        ラジアン::生成する(0.0),
        ラジアン::生成する(摂動の角のラジアン),
        ラジアン::生成する(0.0),
    );
    場面.箱の配置 = 回す前の配置.微小回転で回す(摂動);
    if 場面.箱の配置 == 回す前の配置 {
        摂動が姿勢を動かしたか::丸めで消えた
    } else {
        摂動が姿勢を動かしたか::動かした
    }
}
