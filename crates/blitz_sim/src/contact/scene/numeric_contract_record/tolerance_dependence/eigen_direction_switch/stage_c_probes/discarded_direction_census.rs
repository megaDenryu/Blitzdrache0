//! Issue #103の段階Cの第2手の計器が数える、本番が右辺の判定で捨てている向きの集まり(親の2026-09-13の指示)。
//! 求解1つにつき、捨てた向きの固有値を最大の固有値で割った値を桁ごとに数え、条件の悪い向き(相対固有値が 1e-4 より
//! 小さく、かつ右辺の射影が許容差の内側)を別に溜める。
//! これが要るのは、段階Bの表93が円錐を超えた細分で見つけた形の向きが、まれな事故なのか常時現れているのかを、
//! 段階Bの計測が窓の外で数えていないためである。
//! 右辺と許容差の比に使うのは、擬似逆が実際に比べた側の許容差の射影である。本番の適用規則では受理の側の射影と
//! 同じ値であり、捨てた理由が「右辺が許容差の内側」である向きではこの比が必ず1以下になる。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::ill_conditioned_direction_reading::条件の悪い向き一本の読み取り;
use super::ill_conditioned_direction_tally::条件の悪い向きの集まり;
use crate::contact::normal_tangential_system::{単精度の解の内訳, 桁ごとの度数};
use crate::contact::symmetric_system::擬似逆が固有の向きを捨てた理由;

// 桁ごとの度数の範囲。`固有値を最大で割った相対値の広がり`と同じ刻みである。
const いちばん低い桁の下端の十の冪: i32 = -8;
const 数える桁の本数: usize = 9;
const 条件が悪いと読む相対固有値: f64 = 1.0e-4; // 親の指示が読みのために指定した区切りであり、本番の判定と閾値ではない

/// 本番が右辺の判定で捨てた向きの集まり。
pub(super) struct 本番が右辺の判定で捨てた向きの集まり {
    数えた細分の数: usize,
    捨てた向きの延べ本数: usize,
    相対固有値の桁ごとの度数: 桁ごとの度数,
    条件の悪い向き: 条件の悪い向きの集まり,
}

impl 本番が右辺の判定で捨てた向きの集まり {
    pub(super) fn 零から始める() -> Self {
        Self {
            数えた細分の数: 0,
            捨てた向きの延べ本数: 0,
            相対固有値の桁ごとの度数: 桁ごとの度数::範囲から始める(いちばん低い桁の下端の十の冪, 数える桁の本数),
            条件の悪い向き: 条件の悪い向きの集まり::零から始める(),
        }
    }

    /// 細分1本の求解を数える。最大の固有値が正でない求解は数えない。
    pub(super) fn 一細分の求解を数える(&mut self, 細分の番号: usize, 内訳: &単精度の解の内訳) {
        let λ_max = f64::from(内訳.最大の固有値);
        if λ_max <= 0.0 {
            return;
        }
        self.数えた細分の数 += 1;
        let 最も強い向きの並進 = 最も強い向きの並進を読む(内訳);
        for (向きの番号, 向き) in 内訳.固有の向きごと.iter().enumerate() {
            if 向き.捨てた理由 != 擬似逆が固有の向きを捨てた理由::右辺が許容差の内側 {
                continue;
            }
            self.捨てた向きの延べ本数 += 1;
            let 相対固有値 = f64::from(向き.固有値) / λ_max;
            self.相対固有値の桁ごとの度数.一つ数える(向き.固有値 / 内訳.最大の固有値);
            let 読み取り = 条件の悪い向き一本の読み取り {
                細分の番号,
                向きの番号,
                相対固有値,
                右辺の射影を許容差で割った値: 許容差で割った値(向き.右辺の射影, 向き.許容差の射影),
                剛体へ入る並進: f64::from(向き.剛体へ入る補正.並進の長さ.値()),
                剛体へ入る回転: f64::from(向き.剛体へ入る補正.回転の大きさ.値()),
                同じ細分の最も強い向きの並進: 最も強い向きの並進,
            };
            if 相対固有値 < 条件が悪いと読む相対固有値 && 読み取り.右辺の射影を許容差で割った値 < 1.0 {
                self.条件の悪い向き.一本を数える(&読み取り);
            }
        }
    }

    /// 表へ綴る形。
    pub(super) fn 綴り(&self) -> String {
        format!(
            "数えた細分={}個 捨てた向きの延べ本数={}本 相対固有値の桁ごとの度数[{}] 条件の悪い向き({条件が悪いと読む相対固有値:.0e}未満かつ右辺が許容差の内側){{{}}} {}",
            self.数えた細分の数,
            self.捨てた向きの延べ本数,
            self.相対固有値の桁ごとの度数.綴り(),
            self.条件の悪い向き.綴り(),
            self.条件の悪い向き.現れた細分の番号の綴り()
        )
    }
}

// 固有値が最大の向きが剛体へ入れる並進。向きが1本も無ければ零である。
fn 最も強い向きの並進を読む(内訳: &単精度の解の内訳) -> f64 {
    内訳
        .固有の向きごと
        .iter()
        .max_by(|左, 右| 左.固有値.total_cmp(&右.固有値))
        .map_or(0.0, |向き| f64::from(向き.剛体へ入る補正.並進の長さ.値()))
}

// 右辺の射影の大きさを許容差の射影で割った値。許容差が零なら、右辺が零のときだけ零である。
fn 許容差で割った値(右辺の射影: f32, 許容差の射影: f32) -> f64 {
    if 許容差の射影 > 0.0 {
        f64::from(右辺の射影.abs()) / f64::from(許容差の射影)
    } else {
        f64::from(右辺の射影.abs())
    }
}
