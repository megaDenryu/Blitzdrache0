//! Issue #103の段階Cの第2手の計器が読む「条件の悪い向き」1本の読み取り(親の2026-09-13の指示)。
//! 条件の悪い向きとは、本番が右辺の判定で捨てている向きのうち、固有値を最大の固有値で割った値が 1e-4 より小さく、
//! かつ右辺の射影を向きへ積み上げた許容差で割った値が1より小さい向きのことである。段階Bの表93が、円錐を超えた
//! 細分で見つけた形である。区切りの 1e-4 は親の指示が読みのために指定した値であり、本番の判定と閾値ではない。
//! 剛体へ入る並進と回転は、その向きだけを解いたと仮定したときに (β_k ÷ λ_k) v_k を Jᵀ で写した量である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

/// 条件の悪い向き1本の読み取り。表の1行に当たる。
pub(super) struct 条件の悪い向き一本の読み取り {
    pub(super) 細分の番号: usize,
    pub(super) 向きの番号: usize,
    pub(super) 相対固有値: f64,
    pub(super) 右辺の射影を許容差で割った値: f64,
    pub(super) 剛体へ入る並進: f64,
    pub(super) 剛体へ入る回転: f64,
    pub(super) 同じ細分の最も強い向きの並進: f64,
}

impl 条件の悪い向き一本の読み取り {
    /// 同じ細分でいちばん強い向き(固有値が最大の向き)が剛体へ入れる並進に対する比。分母が零なら零である。
    pub(super) fn 最も強い向きの並進への比(&self) -> f64 {
        if self.同じ細分の最も強い向きの並進 > 0.0 {
            self.剛体へ入る並進 / self.同じ細分の最も強い向きの並進
        } else {
            0.0
        }
    }

    /// 表へ綴る形。
    pub(super) fn 綴り(&self) -> String {
        format!(
            "細分{} 向き{} λ/λ_max={:.4e} |β_k|/δ_k={:.4e} 並進={:.4e} 回転={:.4e} 最も強い向きの並進への比={:.4e}",
            self.細分の番号,
            self.向きの番号,
            self.相対固有値,
            self.右辺の射影を許容差で割った値,
            self.剛体へ入る並進,
            self.剛体へ入る回転,
            self.最も強い向きの並進への比()
        )
    }
}
