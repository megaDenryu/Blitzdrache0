//! Issue #103の段階A5の計測3。接線の雑音の床が、箱の腕の長さに比例するかどうかを測る計器(親の2026-09-12の指示)。
//! 段階A3の表46は、正接0.30の緩い坂で回し45度の床が 7.9719e-7メートルであり、回し0度・回し30度・遠方の3つの
//! 床(6.65e-8〜7.33e-8)の10.9倍であることを測った。その段差が丸めから来るなら、床は接触点の腕の大きさに比例する。
//! 腕の長さは回転で保存されるため、比例するなら回しでは変わらないはずであり、比例しないなら段差の由来は丸めでない。
//! そこで箱の半分の長さを 0.25・0.5・1.0 の3つへ振り、同じ回しで床を並べる。回し0度も同じ3つで並べるのは、
//! 45度だけが比例から外れるのか、どの姿勢でも比例しないのかを分けるためである。
//! 床そのものを綴る工程は`tangential_noise_floor`が持ち、この計器は場面の組を差し替えて同じ工程を呼ぶ。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 箱の腕の雑音の床 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use blitz_math::メートル;

use super::super::scene_variation::段階A1の場面からの一つの変更;
use super::tangential_noise_floor::{一つの場面の雑音の床を綴る, 回しを付けた緩い坂の場合};
use crate::contact::normal_tangential_system::試験の許容差の当て方;

fn 一つの回しで腕を振る(鉛直軸まわりの回しの度: f32) {
    // 既定の 0.5 を挟んで半分と2倍を取る。床が腕に比例するなら、両端で4倍の開きが出る。
    for 半分の長さ in [0.25_f32, 0.5, 1.0] {
        一つの場面の雑音の床を綴る(
            &回しを付けた緩い坂の場合(
                段階A1の場面からの一つの変更::箱の半分の長さを変える {
                    長さ: メートル::生成する(半分の長さ),
                },
                鉛直軸まわりの回しの度,
            ),
            試験の許容差の当て方::本番と同じ当て方(),
        );
    }
}

