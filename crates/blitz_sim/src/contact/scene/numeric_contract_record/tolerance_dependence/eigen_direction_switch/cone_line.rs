//! 細分1本の反復ごとの円錐の量を表の行として綴る工程(Issue #103の段階Aの一次計測の計測点6)。段階A1の
//! `record_line`が綴る計測点0と5の行から分けているのは、あちらが接線変位と速さと作り直しの割合を綴る行であり、
//! こちらが円錐の判定が直に読む3つの量(Σλ_n・‖Σλ_t‖・比)を反復ごとに並べる行だからである。Issue #103 の
//! 「最初に測ること」の3が、この3つを倍率ごとに分岐の直前から比べることを求めている。合否は判定しない。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::iteration_reading::反復の後の読み取り;
use super::super::substep_record::許容差依存の細分の記録;

impl 許容差依存の細分の記録 {
    /// 反復ごとの Σλ_n・‖Σλ_t‖・円錐の比・滑走中の点の数を1行に綴る。
    pub(super) fn 円錐の量を反復ごとに綴る(&self) {
        let 反復ごと: Vec<String> = self.反復ごと.iter().enumerate().map(反復1つを綴る).collect();
        println!(
            "  E 細分{} 入口Σ|Δt|={:.4e} δ_t={:.4e} | {}",
            self.番号,
            self.入口の接線変位の合計,
            self.接線の行の許容差,
            反復ごと.join(" | ")
        );
    }
}

fn 反復1つを綴る((番号, 反復): (usize, &反復の後の読み取り)) -> String {
    format!(
        "反復{番号}後 Σλ_n={:.6e} ‖Σλ_t‖={:.6e} 比={:.6} 滑走{} 解けず{}",
        反復.法線の乗数の合計,
        反復.接線の合力の大きさ,
        反復.円錐の比(),
        反復.滑走中の点の数,
        反復.解けなかった集合の数
    )
}
