//! Issue #103の段階Bの計器が、本番と枝の差が最初に生じた量を突き止めるために1細分から読む量の並び
//! (親の2026-09-13の指示)。量を名前と綴りの対で持つのは、量を足しても突き合わせ方が変わらないためであり、
//! 12個の量を12個のフィールドへ並べた型が「量を1つ足すたびに比較の式も直す」形になるのを避けるためである。
//! 綴りで比べるのは、綴った桁までが一致するかを見るためである。表へ出す値と突き合わせる値を同じにすると、
//! 表では同じに見えるのに差が在ると報告される食い違いが起きない。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::substep_record::許容差依存の細分の記録;
use crate::contact::normal_tangential_system::単精度の解の内訳;
use crate::contact::symmetric_system::擬似逆が固有の向きを捨てた理由;

/// 細分1本から読んだ、名前を付けた量の並び。
pub(super) struct 細分一本から読んだ名前つきの量の並び {
    量: Vec<(&'static str, String)>,
}

impl 細分一本から読んだ名前つきの量の並び {
    /// 細分の記録から読む。入口の内訳が無い細分では、連立に由来する量を「内訳が無い」と綴る。
    pub(super) fn 細分の記録から読む(記録: &許容差依存の細分の記録) -> Self {
        let 内訳 = 記録.入口.as_ref().and_then(|入口| 入口.一倍の内訳.as_ref());
        let 反復零 = 記録.反復ごと.first();
        let 反復が無い = || "反復が無い".to_owned();
        let mut 量 = vec![
            ("接触点の数", format!("{}", 記録.終わりの接触点ごと.len())),
            ("接触点の特徴の識別の並び", 特徴の識別の並び(記録)),
            ("錨を置き直した点の数", format!("{}", 記録.置き直した点の数())),
            ("滑走中の点の数", format!("{}", 記録.滑走中の点の数())),
            (
                "反復零の後の法線の乗数の合計",
                反復零.map_or_else(反復が無い, |読み| format!("{:.6e}", 読み.法線の乗数の合計)),
            ),
            (
                "反復零の後の接線の合力の大きさ",
                反復零.map_or_else(反復が無い, |読み| format!("{:.6e}", 読み.接線の合力の大きさ)),
            ),
            (
                "反復零の後の円錐の比",
                反復零.map_or_else(反復が無い, |読み| format!("{:.6e}", 読み.円錐の比())),
            ),
            ("細分の終わりの接線変位の合計", format!("{:.6e}", 記録.終わりの接線変位の合計())),
        ];
        量.extend(内訳.map_or_else(内訳が無いときの量, 連立に由来する量));
        Self { 量 }
    }

    /// 相手と綴りが違う量の名前の並び。並びの長さが同じであることは呼び出し側が同じ細分を渡すことで保つ。
    pub(super) fn 相手と違う量の名前(&self, 相手: &Self) -> Vec<&'static str> {
        self.量
            .iter()
            .zip(相手.量.iter())
            .filter(|((_, 自分), (_, 相手))| 自分 != 相手)
            .map(|((名前, _), _)| *名前)
            .collect()
    }
}

fn 特徴の識別の並び(記録: &許容差依存の細分の記録) -> String {
    let 並び: Vec<String> = 記録.終わりの接触点ごと.iter().map(|点| format!("{:?}", 点.特徴の識別())).collect();
    並び.join(",")
}

fn 内訳が無いときの量() -> Vec<(&'static str, String)> {
    [
        "有効集合",
        "連立の行数",
        "偽の固有値で捨てた本数",
        "右辺の判定で捨てた本数",
        "行ごとの残差の最大",
    ]
    .into_iter()
    .map(|名前| (名前, "内訳が無い".to_owned()))
    .collect()
}

fn 連立に由来する量(内訳: &単精度の解の内訳) -> Vec<(&'static str, String)> {
    vec![
        ("有効集合", 内訳.有効集合の綴り()),
        ("連立の行数", format!("{}", 内訳.行ごとの残差.len())),
        (
            "偽の固有値で捨てた本数",
            format!("{}", 内訳.捨てた向きの数(擬似逆が固有の向きを捨てた理由::偽の固有値)),
        ),
        (
            "右辺の判定で捨てた本数",
            format!("{}", 内訳.捨てた向きの数(擬似逆が固有の向きを捨てた理由::右辺が許容差の内側)),
        ),
        ("行ごとの残差の最大", format!("{:.6e}", 内訳.行ごとの残差の最大())),
    ]
}
