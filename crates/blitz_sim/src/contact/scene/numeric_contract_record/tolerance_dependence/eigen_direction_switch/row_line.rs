//! 第一反復の入口の読み取りのうち、行ごとの乗数の増分と元の行空間の残差を倍率1倍と2倍で並べて綴る工程
//! (Issue #103の段階Aの一次計測の計測点7)。段階A1の`direction_line`が綴る計測点1と2から分けているのは、
//! あちらが固有の向きの空間の量(固有値・右辺の射影・許容差の射影)を綴り、こちらが元の行の空間の量(その行の
//! 乗数の増分・残差・受理の許容差 δ_i・許容差の内側として捨てた右辺)を綴るからである。Issue #103 の
//! 「最初に測ること」の2が、捨てた向きを元の行空間へ戻した残差がどの行の δ_i と比べられ、どの行の乗数の配分を
//! 変えるかを求めている。行の並びは法線の行が先で接線の行が後であり、どちらの群でも有効な点の番号の昇順である
//! (`row_order`)。点の番号は同じ行に綴る有効集合のビット並びから読む。合否は判定しない。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::entry_reading::第一反復の入口の読み取り;
use crate::contact::normal_tangential_system::単精度の解の内訳;

impl 第一反復の入口の読み取り {
    /// 計測点7(行ごとの乗数の増分と元の行空間の残差)を綴る。
    pub(super) fn 計測点七を綴る(&self) {
        match (&self.一倍の内訳, &self.二倍の内訳) {
            (Some(一倍), Some(二倍)) if 一倍.有効集合 == 二倍.有効集合 => 二つの内訳の行を並べて綴る(一倍, 二倍),
            (Some(_), Some(_)) => println!("    D 有効集合が違うため行が対応しない"),
            _ => println!("    D 内訳が定まらず"),
        }
    }
}

fn 二つの内訳の行を並べて綴る(一倍: &単精度の解の内訳, 二倍: &単精度の解の内訳) {
    for k in 0..一倍.行ごとの残差.len() {
        println!(
            "    D 行{k}({}) Δλ 1倍={:.6e} 2倍={:.6e} 差={:.3e} | 残差 1倍={:.3e} 2倍={:.3e} | δ_i 1倍={:.3e} 2倍={:.3e} | 捨てた右辺 1倍={:.3e} 2倍={:.3e}",
            行の持ち主の綴り(一倍, k),
            一倍.行ごとの乗数の増分[k],
            二倍.行ごとの乗数の増分[k],
            二倍.行ごとの乗数の増分[k] - 一倍.行ごとの乗数の増分[k],
            一倍.行ごとの残差[k],
            二倍.行ごとの残差[k],
            一倍.行ごとの解けたと見なす許容差[k],
            二倍.行ごとの解けたと見なす許容差[k],
            一倍.行ごとの許容差の内側として捨てた右辺[k],
            二倍.行ごとの許容差の内側として捨てた右辺[k],
        );
    }
}

// 第k行が法線の行か接線の行かと、その群の中で何番目か。
fn 行の持ち主の綴り(内訳: &単精度の解の内訳, k: usize) -> String {
    if k < 内訳.法線の行の数 {
        format!("法線の{k}番目")
    } else {
        format!("接線の{}番目", k - 内訳.法線の行の数)
    }
}
