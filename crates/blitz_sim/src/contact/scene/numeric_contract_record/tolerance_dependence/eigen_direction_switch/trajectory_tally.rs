//! 1本の軌道を600刻み走らせるあいだに数える量(Issue #103の段階Aと段階A2の一次計測)。軌道を進める工程
//! (`trajectory`)から分けているのは、あちらが細分を進めて行ごとの量を綴る工程であり、こちらが走行の全体について
//! 1行に畳む数えだからである。数えるのは、退避の理由ごとの延べ数・最初に滑走した細分・窓の円錐の比の範囲・
//! 窓で採否が変わった固有の向きの延べ件数・窓の乗数の増分の絶対値の最大の5つである。
//! 円錐の比の範囲を窓に限るのは、段階Aの表33が窓の範囲で振れ幅を測っており、候補の軌道と同じ範囲で比べるためである。
//! 乗数の増分の最大を数えるのは、候補(α)が捨てる向きを解くことで乗数が桁で膨れないかを見るためである
//! (正則化を退けた理由の事故は、真の増分1.5e-5に対して5.2e-3であった)。
//! 右辺の判定が捨てた向きを2つの群に分けて数えるのは、段階A3の候補(θ)が「物理的に意味のある向きを解き、階数不足の
//! 向きは捨て続ける」ことを狙う枝であり、その狙いが当たったかを延べ数で読むためである。群の境は λ_k ÷ λ_max であり、
//! 段階A2の実測(捨てられた真の向きは λ_max の21〜57パーセント、階数側は 2e-6 の桁)から 1e-3 を境に置く。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use std::collections::BTreeMap;

use super::super::substep_record::許容差依存の細分の記録;
use crate::contact::normal_tangential_system::単精度の解の内訳;
use crate::contact::symmetric_system::擬似逆が固有の向きを捨てた理由;

// 固有の向きを「物理的に意味のある向き」と読む、最大の固有値に対する相対値の下限。
const 真の向きと読む相対値: f32 = 1.0e-3;

/// 1本の軌道の走行を1行へ畳む数え。
pub(super) struct 一本の軌道の集計 {
    退避の理由ごとの延べ数: BTreeMap<&'static str, usize>,
    最初に滑走した細分: Option<usize>,
    窓の円錐の比の最小: f64,
    窓の円錐の比の最大: f64,
    窓の採否が変わった向きの延べ件数: usize,
    窓の乗数の増分の絶対値の最大: f32,
    窓で右辺の判定が捨てた真の向きの延べ数: usize,
    窓で右辺の判定が捨てた階数側の向きの延べ数: usize,
}

impl 一本の軌道の集計 {
    pub(super) fn 零から始める() -> Self {
        Self {
            退避の理由ごとの延べ数: BTreeMap::new(),
            最初に滑走した細分: None,
            窓の円錐の比の最小: f64::INFINITY,
            窓の円錐の比の最大: 0.0,
            窓の採否が変わった向きの延べ件数: 0,
            窓の乗数の増分の絶対値の最大: 0.0,
            窓で右辺の判定が捨てた真の向きの延べ数: 0,
            窓で右辺の判定が捨てた階数側の向きの延べ数: 0,
        }
    }

    /// 細分1本の記録を数える。窓の中かどうかは呼び出し側が決める。
    pub(super) fn 一細分を数える(&mut self, 記録: &許容差依存の細分の記録, 窓の中か: bool) {
        for (_, 読み取り) in &記録.解けなかった連立 {
            *self.退避の理由ごとの延べ数.entry(読み取り.結末の綴り).or_insert(0) += 1;
        }
        if self.最初に滑走した細分.is_none() && 記録.滑走中か() {
            self.最初に滑走した細分 = Some(記録.番号);
        }
        if !窓の中か || 記録.滑走中か() {
            return;
        }
        let 比 = 記録.最後の反復の後の円錐の比();
        self.窓の円錐の比の最小 = self.窓の円錐の比の最小.min(比);
        self.窓の円錐の比の最大 = self.窓の円錐の比の最大.max(比);
        let Some(入口) = &記録.入口 else { return };
        self.窓の採否が変わった向きの延べ件数 += 入口.採否が変わった向き().len();
        for 内訳 in [&入口.一倍の内訳, &入口.二倍の内訳].into_iter().flatten() {
            let 最大 = 内訳.行ごとの乗数の増分.iter().map(|増分| 増分.abs()).fold(0.0, f32::max);
            self.窓の乗数の増分の絶対値の最大 = self.窓の乗数の増分の絶対値の最大.max(最大);
        }
        if let Some(内訳) = 入口.一倍の内訳.as_ref() {
            self.右辺の判定が捨てた向きを群ごとに数える(内訳);
        }
    }

    // 右辺の判定 |β_k| ≤ δ_k で捨てられた向きを、λ_k ÷ λ_max が 1e-3 以上の群とそれ未満の群に分けて数える。
    fn 右辺の判定が捨てた向きを群ごとに数える(&mut self, 内訳: &単精度の解の内訳) {
        for 向き in &内訳.固有の向きごと {
            if 向き.捨てた理由 != 擬似逆が固有の向きを捨てた理由::右辺が許容差の内側 {
                continue;
            }
            let 相対値 = if 内訳.最大の固有値 > 0.0 {
                向き.固有値 / 内訳.最大の固有値
            } else {
                0.0
            };
            if 相対値 >= 真の向きと読む相対値 {
                self.窓で右辺の判定が捨てた真の向きの延べ数 += 1;
            } else {
                self.窓で右辺の判定が捨てた階数側の向きの延べ数 += 1;
            }
        }
    }

    /// 表へ綴る形。
    pub(super) fn 綴り(&self) -> String {
        let 内訳: Vec<String> = self.退避の理由ごとの延べ数.iter().map(|(理由, 数)| format!("{理由}={数}")).collect();
        format!(
            "最初に滑走した細分={:?} 退避{}[{}] 窓の比={:.6}〜{:.6}(幅{:.4}) 窓の採否変更{}件 窓の|Δλ|最大={:.4e} 窓で右辺の判定が捨てた向き(真={} 階数側={})",
            self.最初に滑走した細分,
            self.退避の理由ごとの延べ数.values().sum::<usize>(),
            内訳.join(" "),
            self.窓の円錐の比の最小,
            self.窓の円錐の比の最大,
            self.窓の円錐の比の最大 - self.窓の円錐の比の最小,
            self.窓の採否が変わった向きの延べ件数,
            self.窓の乗数の増分の絶対値の最大,
            self.窓で右辺の判定が捨てた真の向きの延べ数,
            self.窓で右辺の判定が捨てた階数側の向きの延べ数
        )
    }
}
