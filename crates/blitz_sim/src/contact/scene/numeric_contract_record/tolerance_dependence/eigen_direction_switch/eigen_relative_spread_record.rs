// 1つの場面を細分16本進め、細分ごとの相対値の並びと、全部の細分を通した広がりを綴る。
fn 一つの場面の相対分布を綴る(場合: &許容差依存の診断の場合) {
    let 条件 = 場合.坂の場面の条件を組む();
    let mut 場面 = 場合.場面を当て方で組む(試験の許容差の当て方::本番と同じ当て方());
    let mut 広がり = 固有値を最大で割った相対値の広がり::零から始める();
    println!("[{}] 細分0〜{} 固有値を最大で割った相対値", 場合.見出し(), 綴る細分の本数 - 1);
    for 番号 in 0..綴る細分の本数 {
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, true);
        let Some(内訳) = 記録.入口.as_ref().and_then(|入口| 入口.一倍の内訳.as_ref()) else {
            println!("  K 細分{番号} 粘着の候補が定まらず");
            continue;
        };
        広がり.一回の求解を数える(内訳);
        let 相対値: Vec<String> = 内訳
            .固有の向きごと
            .iter()
            .map(|向き| format!("{:.3e}", 向き.固有値 / 内訳.最大の固有値))
            .collect();
        println!(
            "  K 細分{番号} 行数={} λ_max={:.4e} 相対値={}",
            内訳.固有の向きごと.len(),
            内訳.最大の固有値,
            相対値.join(",")
        );
    }
    println!("  要約 [{}] {}", 場合.見出し(), 広がり.綴り());
}

