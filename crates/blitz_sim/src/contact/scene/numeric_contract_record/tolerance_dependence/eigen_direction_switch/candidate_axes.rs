//! 2つの設計候補の軸へ差し替えて受理の倍率1倍と2倍の2本ずつ走らせ、段階Aの表33と表34と同じ量を並べる。
//! 候補(α)は擬似逆の右辺の判定 |β_k| ≤ δ_k を当てず、偽の固有値でない向きを全部解く枝である。
