//! 窓は段階Aと同じ細分3320〜3345であり、円錐の比の振れ幅(段階Aの実測は1倍が0.0078、2倍が0.0328)と、
//! 採否が変わった固有の向きの件数(段階Aの実測は21件)と、退避の件数と理由と、乗数の増分の絶対値の最大を同じ範囲で比べる。
