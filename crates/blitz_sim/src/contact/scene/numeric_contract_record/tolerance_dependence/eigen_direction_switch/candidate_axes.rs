use crate::contact::normal_tangential_system::{
    擬似逆が右辺の向きを捨てる判定の当て方, 解けたと見なす許容差の倍率, 解けたと見なす許容差を導く座標の由来, 試験の許容差の当て方,
};

const 振る受理の倍率: [f32; 2] = [1.0, 2.0];

fn 窓() -> 細分を綴る窓 {
    細分を綴る窓::入口も読む {
        始まりの細分: 窓の始まりの細分(),
        終わりの細分: 窓の終わりの細分(),
    }
}

// 1つの候補の適用規則を、受理の倍率1倍と2倍の2本の軌道で走らせる。
fn 一つの候補を倍率ごとに綴る(候補の適用規則: 試験の許容差の当て方) {
    for 比 in 振る受理の倍率 {
        let 適用規則 = 候補の適用規則.受理の倍率を差し替える(解けたと見なす許容差の倍率::比から生成する(比));
        一本の軌道を窓つきで綴る(&遠方の正接零点五八の場合(), 適用規則, 窓());
    }
}

