//! その向きを捨てずに解いたときの増分 |β_k| ÷ λ_k の最大を綴る。候補(α)は下限のすぐ上の向きも解くため、
//! そこに向きが居れば増分が桁で膨れる。居なければ候補(α)の事故はこの場面では実在しない。
//! 塔の側は `crates/blitz_sim/src/contact/pipeline/tower_eigen_distribution_record.rs` が別に綴る(あちらは剛体どうしの接触であり、
