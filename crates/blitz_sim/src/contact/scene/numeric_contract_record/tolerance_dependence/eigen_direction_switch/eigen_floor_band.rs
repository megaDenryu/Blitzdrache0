//! 実行は `cargo test -p blitz_sim --release 偽の固有値の下限の帯_坂 -- --ignored --nocapture` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::case::許容差依存の診断の場合;
use super::super::scene_variation::段階A1の場面からの一つの変更;
use crate::contact::normal_tangential_system::{
    偽の固有値の下限に対する固有の向きの分布, 接線の行への許容差の当て方
};

const 綴る細分の本数: usize = 16;
const 原点付近の傾きの正接: f32 = 0.55;

fn 原点付近の正接零点五五の場合() -> 許容差依存の診断の場合 {
    許容差依存の診断の場合 {
        静止摩擦係数の値: 0.6,
        傾きの正接: 原点付近の傾きの正接,
        鉛直軸まわりの回しの度: 0.0,
        許容差の比: 1.0,
        行への許容差の当て方: 接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする,
        変更: 段階A1の場面からの一つの変更::無し,
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 偽の固有値の下限の帯_坂の細分十六本を綴る() {
    let 場合 = 原点付近の正接零点五五の場合();
    let 条件 = 場合.坂の場面の条件を組む();
    let mut 場面 = 場合.場面を組む();
    println!(
        "[{}] 細分0〜{} 偽の固有値の下限に対する固有の向きの分布",
        場合.見出し(),
        綴る細分の本数 - 1
    );
    let mut 帯に居た細分の数 = 0;
    for 番号 in 0..綴る細分の本数 {
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, true);
        let Some(内訳) = 記録.入口.as_ref().and_then(|入口| 入口.一倍の内訳.as_ref()) else {
            println!("  G 細分{番号} 内訳が定まらず");
            continue;
        };
        let 分布 = 偽の固有値の下限に対する固有の向きの分布::内訳から読む(内訳);
        帯に居た細分の数 += usize::from(分布.下限のすぐ上に居る向きの本数() > 0);
        println!("  G 細分{番号} {}", 分布.綴り());
    }
    println!("  要約 [{}] 帯に向きが居た細分={帯に居た細分の数}本 / {綴る細分の本数}本", 場合.見出し());
}
