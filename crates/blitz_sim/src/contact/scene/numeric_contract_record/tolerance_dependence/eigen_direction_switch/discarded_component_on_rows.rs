// 定常へ達した後の窓。段階A5の計測1は、回し45度が細分21で定常へ達することを測った。
const 綴る窓: (usize, usize) = (60, 63);

// 行ごとの δ_i・残差・許容差の内側として捨てた右辺を綴る。
fn 行ごとを綴る(番号: usize, 内訳: &単精度の解の内訳) {
    for 行 in 0..内訳.行ごとの残差.len() {
        let 種別 = if 行 < 内訳.法線の行の数 { "法線" } else { "接線" };
        println!(
            "    X 細分{番号} {種別}の行{行} δ_i={:.4e} 残差={:.4e} 許容差の内側として捨てた右辺={:.4e}",
            内訳.行ごとの解けたと見なす許容差[行], 内訳.行ごとの残差[行], 内訳.行ごとの許容差の内側として捨てた右辺[行]
        );
    }
}

// 向きごとの固有値・右辺の射影・許容差の射影・捨てた理由・不確かさの率・増分を綴る。
fn 向きごとを綴る(番号: usize, 内訳: &単精度の解の内訳) {
    let 硬い向きの増分 = 内訳.右辺をいちばん硬い向きで解いたときの増分();
    for (k, 向き) in 内訳.固有の向きごと.iter().enumerate() {
        let (率, 増分) = if 向き.固有値 > 0.0 {
            (内訳.偽の固有値の下限 / 向き.固有値, (向き.右辺の射影 / 向き.固有値).abs())
        } else {
            (f32::INFINITY, 0.0)
        };
        println!(
            "    Y 細分{番号} 向き{k} λ={:.4e} λ/λ_max={:.4e} |β|={:.4e} δ_k={:.4e} 理由={:?} 不確かさの率={率:.4e} 増分={増分:.4e} 正規化した増分={:.4e}",
            向き.固有値,
            向き.固有値 / 内訳.最大の固有値,
            向き.右辺の射影.abs(),
            向き.許容差の射影,
            向き.捨てた理由,
            if 硬い向きの増分 > 0.0 {
                増分 / 硬い向きの増分
            } else {
                0.0
            }
        );
    }
}

fn 一細分を綴る(記録: &許容差依存の細分の記録) {
    let 番号 = 記録.番号;
    let Some(内訳) = 記録.入口.as_ref().and_then(|入口| 入口.一倍の内訳.as_ref()) else {
        println!("  X 細分{番号} 粘着の候補が定まらず");
        return;
    };
    println!(
        "  X 細分{番号} 有効集合={} 行数={} λ_max={:.4e} 偽の固有値の下限={:.4e} ‖b‖={:.4e}",
        内訳.有効集合の綴り(),
        内訳.行ごとの残差.len(),
        内訳.最大の固有値,
        内訳.偽の固有値の下限,
        内訳.右辺の大きさ
    );
    行ごとを綴る(番号, 内訳);
    向きごとを綴る(番号, 内訳);
}

fn 一つの回しの窓を綴る(鉛直軸まわりの回しの度: f32) {
    let 場合 = 回しを付けた緩い坂の場合(段階A1の場面からの一つの変更::無し, 鉛直軸まわりの回しの度);
    let 条件 = 場合.坂の場面の条件を組む();
    let mut 場面 = 場合.場面を当て方で組む(試験の許容差の当て方::本番と同じ当て方());
    println!("[{}] 細分{}〜{} の捨てた成分と行の残差", 場合.見出し(), 綴る窓.0, 綴る窓.1);
    for 番号 in 0..=綴る窓.1 {
        let 窓の中か = 番号 >= 綴る窓.0;
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, 窓の中か);
        if 窓の中か {
            一細分を綴る(&記録);
        }
    }
}

