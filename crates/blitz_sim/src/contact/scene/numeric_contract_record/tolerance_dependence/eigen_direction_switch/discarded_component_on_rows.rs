//! Issue #103の段階A5の計測9。緩い坂(正接0.30)の回し45度が定常に達した細分で、擬似逆が捨てた向きと、その成分を
//! 元の行へ戻した量を、行ごとの残差と対にして綴る計器(親の2026-09-12の指示)。
//! これが要るのは、段階A5の計測2が「接線の行は全部積まれ、連立方程式は解け、受理も通っているのに、元の行空間の残差が
//! 回し45度だけ他の姿勢の30倍になり、箱が釣り合う接線変位はその残差と同じ桁である」ことを測ったためである。
//! 残差が擬似逆の捨てた向きで説明できるなら、私たちが「接線の雑音の床」と呼んできた量は丸めが作る雑音ではなく、
//! この issue が所有する捨てる規則が自分で作っている量である。
//! 綴るのは2段である。1段目は行ごとの δ_i・残差・許容差の内側として捨てた右辺(Σ_k β_k v_ik そのもの)であり、
//! 2段目は向きごとの λ_k・λ_k ÷ λ_max・|β_k|・δ_k・捨てた理由・不確かさの率・増分である。
//! 4番目の量(捨てた向きの不確かさの率)が小さければ、その向きは行列の丸めに左右されずよく決まっており、
//! 増分の不確かさで捨てるかどうかを決める形はその向きを解く。1に近ければ、その形もその向きを捨てる。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 捨てた成分と行の残差 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

