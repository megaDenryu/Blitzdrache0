#![cfg(test)]

use super::super::case::許容差依存の診断の場合;
use super::super::scene_variation::段階A1の場面からの一つの変更;
use super::super::stage_c::classification::分類と退避を当て方で綴る;
use super::noise_floor_discard::候補シータの適用規則;
use crate::contact::normal_tangential_system::{
    接線の行への許容差の当て方, 解けたと見なす許容差の倍率, 試験の許容差の当て方
};

const 行列の正接: &[f32] = &[0.50, 0.55, 0.61];
const 行列の回しの度: &[f32] = &[0.0, 30.0, 45.0];
const 振る受理の倍率: &[f32] = &[0.5, 1.0, 2.0];

fn 本番の場合(
    傾きの正接: f32, 鉛直軸まわりの回しの度: f32, 変更: 段階A1の場面からの一つの変更
) -> 許容差依存の診断の場合 {
    許容差依存の診断の場合 {
        静止摩擦係数の値: 0.6,
        傾きの正接,
        鉛直軸まわりの回しの度,
        許容差の比: 1.0,
        行への許容差の当て方: 接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする,
        変更,
    }
}

// 1つの適用規則で、27組と細分16本の正接0.55の3方向を綴る。
fn 一つの適用規則の退行を綴る(適用規則: 試験の許容差の当て方) {
    for &倍率 in 振る受理の倍率 {
        let 振った = 適用規則.受理の倍率を差し替える(解けたと見なす許容差の倍率::比から生成する(倍率));
        for &回し in 行列の回しの度 {
            for &正接 in 行列の正接 {
                分類と退避を当て方で綴る(&本番の場合(正接, 回し, 段階A1の場面からの一つの変更::無し), 振った);
            }
        }
    }
    for &回し in 行列の回しの度 {
        分類と退避を当て方で綴る(&本番の場合(0.55, 回し, 段階A1の場面からの一つの変更::細分数を十六にする), 適用規則);
    }
}

