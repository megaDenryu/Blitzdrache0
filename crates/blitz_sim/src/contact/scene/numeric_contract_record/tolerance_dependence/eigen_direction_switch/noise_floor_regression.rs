//! Issue #103の段階A3の計測E。候補(θ)が遠方の正接0.58を受理の倍率3つとも保持したときに、他の場面で退行が無いかを
//! 本番の形と対で綴る計器(親の2026-09-12の指示)。並べるのは、27組(正接0.50・0.55・0.61 × 回し0・30・45度 ×
//! 受理の倍率0.5・1・2倍)と、細分16本の正接0.55の3方向である。箱10段の塔の休止の刻みは
//! `crates/blitz_sim/src/contact/pipeline/stage_a3/tower_rest_step.rs` が別に綴る。
//! 1組ごとに600刻み走らせ、分類・坂に沿った変位・退避の件数と理由・錨の置き直しを1行へ綴る工程は、段階Cの検収が
//! 使う`stage_c::classification`と同じものを呼ぶ。同じ量を同じ形で比べるためであり、退行の判定は親が行う。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
