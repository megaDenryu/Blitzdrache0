// 親が出発点として選んだ2つの値。増分の倍率は段階A5の計測5が壊す向きと読んだ線、率の閾値はそこでの率の最小である。
const 増分の倍率の出発点: f32 = 100.0;
const 率の閾値の出発点: f32 = 9.0e-2;
const 遠方の分類を綴る刻み数: usize = 600;

fn 捨て方を当てた適用規則(捨て方: 本番の代わりに置く右辺の向きの捨て方) -> 試験の許容差の当て方 {
    試験の許容差の当て方::本番と同じ当て方().右辺の向きを捨てる判定を差し替える(
        擬似逆が右辺の向きを捨てる判定の当て方::本番の代わりの規則で捨てる { 捨て方 },
    )
}

fn 二つの捨て方() -> Vec<(String, 本番の代わりに置く右辺の向きの捨て方)> {
    vec![
        (
            format!("増分の大きさで捨てる_倍率{増分の倍率の出発点}"),
            本番の代わりに置く右辺の向きの捨て方::増分が大きい向きを捨てる {
                増分の倍率: 増分の倍率の出発点,
            },
        ),
        (
            format!("不確かさの率で捨てる_閾値{率の閾値の出発点}"),
            本番の代わりに置く右辺の向きの捨て方::不確かさの率が大きい向きを捨てる {
                率の閾値: 率の閾値の出発点
            },
        ),
    ]
}

// 遠方の正接0.58を1つの適用規則と1つの受理の倍率で走らせ、分類と変位を綴る。
fn 遠方の一本を綴る(見出し: &str, 比: f32, 適用規則: 試験の許容差の当て方) {
    let 場合 = 遠方の正接零点五八の場合();
    let 条件 = 場合.坂の場面の条件を組む();
    let mut 場面 = 場合.場面を当て方で組む(適用規則.受理の倍率を差し替える(解けたと見なす許容差の倍率::比から生成する(比)));
    let 初めの重心 = 場面.箱の配置.重心の位置();
    場面.細分を進める(遠方の分類を綴る刻み数 * 場合.変更.一刻みの細分数());
    println!(
        "  Z [{見出し}_受理{比}倍] 坂に沿った変位={:.4e} 滑走中の点={} 粘着の候補が解けず={} 置き直し={}",
        場面.坂に沿った変位(初めの重心, &条件),
        場面.直前の細分の観測.滑走中の接触点の数,
        場面.粘着の候補が解けなかった接触点集合の延べ数,
        場面.錨を置き直した細分の延べ数
    );
}

