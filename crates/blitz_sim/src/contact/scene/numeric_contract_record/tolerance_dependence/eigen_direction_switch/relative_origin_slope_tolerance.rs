//! Issue #103の段階A4の計測D。回し45度の緩い坂(正接0.30)を候補(θ')で進め、その連立方程式の行ごとの δ_i を
//! 2つの由来で綴り、同じ場面で測った接線の雑音の床と比べる計器(親の2026-09-12の指示)。
//! この場面を選ぶのは、段階A3の表46が測った床のうち回し45度だけが 7.9719e-7メートルと1桁大きく、候補(θ)が据えた
//! 1つの長さ 2.66e-7 をその床が上回っていたためである。候補(θ')の δ_i は座標でなく腕の大きさで決まるため、
//! この床の下へ入るかどうかが枝の成否を分ける。下へ入るなら、雑音でしかない右辺の成分を擬似逆が解くことになる。
//! 綴るのは、細分ごとの |C_t| の最大と、入口を読む細分での行ごとの δ_i(基準原点に相対な座標から導く側と、
//! 粗い位置から導く側)である。入口の読み取りは倍精度の参照計算を伴って高くつくため、8細分ごとに読む。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 基準原点の坂の許容差 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::scene_variation::段階A1の場面からの一つの変更;
use super::super::substep_record::許容差依存の細分の記録;
use super::relative_origin_discard::候補シータダッシュの適用規則;
use super::tangential_noise_floor::回しを付けた緩い坂の場合;

const 綴る細分の本数: usize = 64;
const 入口を読む細分の間隔: usize = 8;
const 鉛直軸まわりの回しの度: f32 = 45.0;

// 入口を読んだ細分の行ごとの δ_i を2つの由来で綴る。入口を読まなかった細分では何も綴らない。
fn 一細分の許容差を綴る(番号: usize, 記録: &許容差依存の細分の記録) {
    let Some(内訳) = 記録.入口.as_ref().and_then(|入口| 入口.一倍の内訳.as_ref()) else {
        return;
    };
    println!(
        "    R 細分{番号} 法線の行={}本 δ_i(基準原点に相対)={:?} δ_i(粗い位置)={:?}",
        内訳.法線の行の数,
        内訳
            .行ごとの基準原点に相対な座標から導く許容差
            .iter()
            .map(|δ| format!("{δ:.4e}"))
            .collect::<Vec<_>>(),
        内訳.行ごとの解けたと見なす許容差.iter().map(|δ| format!("{δ:.4e}")).collect::<Vec<_>>()
    );
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 基準原点の坂の許容差_回し四十五度の緩い坂を候補シータダッシュで綴る() {
    let 場合 = 回しを付けた緩い坂の場合(段階A1の場面からの一つの変更::無し, 鉛直軸まわりの回しの度);
    let 条件 = 場合.坂の場面の条件を組む();
    let mut 場面 = 場合.場面を当て方で組む(候補シータダッシュの適用規則());
    let 初めの重心 = 場面.箱の配置.重心の位置();
    println!(
        "[{}_候補シータダッシュ] 細分0〜{} の許容差と接線の雑音",
        場合.見出し(),
        綴る細分の本数 - 1
    );
    let mut 全体の最大 = 0.0f64;
    let (mut 基準原点由来の最小, mut 基準原点由来の最大) = (f64::INFINITY, 0.0f64);
    for 番号 in 0..綴る細分の本数 {
        let 入口を読むか = 番号.is_multiple_of(入口を読む細分の間隔);
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, 入口を読むか);
        let 最大 = 記録.終わりの接線変位.iter().fold(0.0f64, |合計, 値| 合計.max(値.abs()));
        全体の最大 = 全体の最大.max(最大);
        if let Some(内訳) = 記録.入口.as_ref().and_then(|入口| 入口.一倍の内訳.as_ref()) {
            for δ in &内訳.行ごとの基準原点に相対な座標から導く許容差 {
                基準原点由来の最小 = 基準原点由来の最小.min(f64::from(*δ));
                基準原点由来の最大 = 基準原点由来の最大.max(f64::from(*δ));
            }
        }
        println!("  R 細分{番号} |C_t|の最大={最大:.4e} δ_t(粗い位置)={:.4e}", 記録.接線の行の許容差);
        一細分の許容差を綴る(番号, &記録);
    }
    println!(
        "  要約 [{}_候補シータダッシュ] |C_t|の最大={全体の最大:.4e} δ_i(基準原点に相対)={基準原点由来の最小:.4e}〜{基準原点由来の最大:.4e} 床に対する比={:.3}〜{:.3} 坂に沿った変位={:.3e}",
        場合.見出し(),
        基準原点由来の最小 / 全体の最大,
        基準原点由来の最大 / 全体の最大,
        場面.坂に沿った変位(初めの重心, &条件)
    );
}
