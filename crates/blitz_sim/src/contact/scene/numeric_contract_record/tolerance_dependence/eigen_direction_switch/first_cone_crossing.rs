//! Issue #103の段階A6の追補の計器。細分16本の正接0.55の坂が最初に滑走へ移る細分を4つの規則で探し、その細分と
//! 手前の3細分について、反復ごとの円錐の量と、擬似逆が捨てた向きの本数を理由ごとに綴る(親の2026-09-12の指示)。
//! これが要るのは、段階A6の表82が「3つの捨て方はこの3方向を3方向とも滑走させる」ことを分類で測っただけであり、
//! どの細分で円錐を超えたかも、その細分の接触点集合の比 ‖Σλ_t‖ ÷ Σλ_n も、捨てた向きの本数の差も読めないためである。
//! 一巡目は入口を読まずに滑走した細分を探し、二巡目は同じ場面を組み直して、その細分と手前だけ入口を読む。
//! 2つに分けるのは、入口の読み取りが1細分につき倍精度の求解を3回走らせるためであり、9600細分の全部では終わらない。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 円錐を最初に超えた細分 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::case::許容差依存の診断の場合;
use super::super::scene_variation::段階A1の場面からの一つの変更;
use super::super::substep_record::許容差依存の細分の記録;
use super::alternative_discard_record::{三つの捨て方, 捨て方を当てた適用規則};
use crate::contact::normal_tangential_system::{単精度の解の内訳, 接線の行への許容差の当て方, 試験の許容差の当て方};
use crate::contact::symmetric_system::擬似逆が固有の向きを捨てた理由;

const 傾きの正接: f32 = 0.55;
const 振る回しの度: &[f32] = &[0.0, 30.0, 45.0];
const 走らせる刻みの数: usize = 600;
const 滑走の手前で綴る細分の本数: usize = 3;

fn 細分十六本の場合(鉛直軸まわりの回しの度: f32) -> 許容差依存の診断の場合 {
    許容差依存の診断の場合 {
        静止摩擦係数の値: 0.6,
        傾きの正接,
        鉛直軸まわりの回しの度,
        許容差の比: 1.0,
        行への許容差の当て方: 接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする,
        変更: 段階A1の場面からの一つの変更::細分数を十六にする,
    }
}

// 一巡目。最初に滑走した細分を探す。入口は読まない。
fn 最初に滑走した細分を探す(場合: &許容差依存の診断の場合, 適用規則: 試験の許容差の当て方) -> Option<usize> {
    let 条件 = 場合.坂の場面の条件を組む();
    let 本数 = 走らせる刻みの数 * 場合.変更.一刻みの細分数();
    let mut 場面 = 場合.場面を当て方で組む(適用規則);
    (0..本数).find(|&番号| 場面.記録しながら一細分進める(番号, &条件, false).滑走中か())
}

// 二巡目。滑走した細分とその手前を、入口を読みながら綴る。
fn 滑走した細分と手前を綴る(
    場合: &許容差依存の診断の場合, 適用規則: 試験の許容差の当て方, 滑走した細分: usize
) {
    let 条件 = 場合.坂の場面の条件を組む();
    let 窓の始まり = 滑走した細分.saturating_sub(滑走の手前で綴る細分の本数);
    let mut 場面 = 場合.場面を当て方で組む(適用規則);
    for 番号 in 0..=滑走した細分 {
        let 窓の中か = 番号 >= 窓の始まり;
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, 窓の中か);
        if 窓の中か {
            記録.円錐の量を反復ごとに綴る();
            捨てた向きの本数を綴る(&記録);
        }
    }
}

// 理由ごとに捨てた向きの本数を数える。
fn 理由ごとの本数(内訳: &単精度の解の内訳, 理由: 擬似逆が固有の向きを捨てた理由) -> usize {
    内訳.固有の向きごと.iter().filter(|向き| 向き.捨てた理由 == 理由).count()
}

fn 捨てた向きの本数を綴る(記録: &許容差依存の細分の記録) {
    let Some(内訳) = 記録.入口.as_ref().and_then(|入口| 入口.一倍の内訳.as_ref()) else {
        println!("    X 細分{} 粘着の候補が定まらず内訳が無い", 記録.番号);
        return;
    };
    println!(
        "    X 細分{} 有効集合={} 向き={}本 偽の固有値で捨てた={}本 右辺の判定で捨てた={}本 解いた={}本",
        記録.番号,
        内訳.有効集合の綴り(),
        内訳.固有の向きごと.len(),
        理由ごとの本数(内訳, 擬似逆が固有の向きを捨てた理由::偽の固有値),
        理由ごとの本数(内訳, 擬似逆が固有の向きを捨てた理由::右辺が許容差の内側),
        理由ごとの本数(内訳, 擬似逆が固有の向きを捨てた理由::捨てていない)
    );
}

fn 一つの適用規則の滑走を綴る(
    場合: &許容差依存の診断の場合, 見出し: &str, 適用規則: 試験の許容差の当て方
) {
    println!("[回し{}度_{見出し}] 細分16本の正接{傾きの正接}", 場合.鉛直軸まわりの回しの度);
    let Some(滑走した細分) = 最初に滑走した細分を探す(場合, 適用規則) else {
        println!("  X {走らせる刻みの数}刻みのあいだ1本も滑走しなかった");
        return;
    };
    println!("  X 最初に滑走した細分={滑走した細分}");
    滑走した細分と手前を綴る(場合, 適用規則, 滑走した細分);
}

