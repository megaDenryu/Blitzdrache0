// 段階A2の追補の表40が開いた窓と同じ範囲。本番の形が破局的な向きを捨てている細分64を覆う。
const 綴る窓: (usize, usize) = (60, 66);

// 細分1本の Σλ_n と行ごとの δ_i と、固有の向きごとの量を綴る。
fn 一細分の向きを綴る(番号: usize, 記録: &許容差依存の細分の記録) {
    let 反復零の法線の乗数の合計 = 記録.反復ごと.first().map_or(0.0, |反復| 反復.法線の乗数の合計);
    let Some(内訳) = 記録.入口.as_ref().and_then(|入口| 入口.一倍の内訳.as_ref()) else {
        println!("  Q 細分{番号} 粘着の候補が定まらず 滑走中={}", 記録.滑走中か());
        return;
    };
    let λ_max = 内訳.固有の向きごと.iter().map(|向き| 向き.固有値).fold(0.0, f32::max);
    println!(
        "  Q 細分{番号} 有効集合={} 行数={} Σλ_n(反復0後)={反復零の法線の乗数の合計:.4e} λ_max={λ_max:.4e} δ_i(擬似逆)={:?} δ_i(受理)={:?}",
        内訳.有効集合の綴り(),
        内訳.固有の向きごと.len(),
        内訳
            .行ごとの基準原点に相対な座標から導く許容差
            .iter()
            .map(|δ| format!("{δ:.3e}"))
            .collect::<Vec<_>>(),
        内訳.行ごとの解けたと見なす許容差.iter().map(|δ| format!("{δ:.3e}")).collect::<Vec<_>>()
    );
    for (k, 向き) in 内訳.固有の向きごと.iter().enumerate() {
        let 増分 = if 向き.固有値 > 0.0 {
            (向き.右辺の射影 / 向き.固有値).abs()
        } else {
            0.0
        };
        println!(
            "    Q 細分{番号} 向き{k} λ={:.4e} λ/λ_max={:.4e} |β|={:.4e} 増分={増分:.4e} δ_k(擬似逆)={:.4e} δ_k(受理)={:.4e} この枝は捨てる={} 増分/Σλ_n={:.4}",
            向き.固有値,
            if λ_max > 0.0 { 向き.固有値 / λ_max } else { 0.0 },
            向き.右辺の射影.abs(),
            向き.許容差の射影,
            向き.受理の許容差の射影,
            向き.右辺の射影.abs() <= 向き.許容差の射影,
            if 反復零の法線の乗数の合計 > 0.0 {
                f64::from(増分) / 反復零の法線の乗数の合計
            } else {
                0.0
            }
        );
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 基準原点の向きの内訳_候補シータダッシュの細分六十から六十六を綴る() {
    let 場合 = 遠方の正接零点五八の場合();
    let 条件 = 場合.坂の場面の条件を組む();
    let mut 場面 = 場合.場面を当て方で組む(候補シータダッシュの適用規則());
    println!("[候補シータダッシュ_受理1倍] 細分{}〜{} の固有の向きの内訳", 綴る窓.0, 綴る窓.1);
    for 番号 in 0..=綴る窓.1 {
        let 窓の中か = 番号 >= 綴る窓.0;
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, 窓の中か);
        if 窓の中か {
            一細分の向きを綴る(番号, &記録);
        }
    }
}
