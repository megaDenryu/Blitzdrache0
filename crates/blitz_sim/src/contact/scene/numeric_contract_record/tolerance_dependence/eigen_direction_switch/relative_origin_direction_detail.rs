//! Issue #103の段階A4の計測C。候補(θ')の軌道の細分60から66について、その連立方程式の固有の向きを1本ずつ綴る計器
//! (親の2026-09-12の指示)。この範囲を開くのは、本番の形の細分64に「解けば Σλ_n の49.6倍の増分を作る向き」
//! (λ = 2.7970e-5、|β| = 5.0956e-8。段階A2の追補の表40)が実在し、本番はそれを δ_k = 3.5640e-6 の内側として
//! 捨てているためである。候補(θ')の δ_i は基準原点に相対な座標から導くため 5e-8 の桁へ下がり、この向きの |β| と
//! 同じ桁に並ぶ。したがって、この枝がその向きを解くか捨てるかは算術で予測できず、測るしかない。
//! 綴るのは、向きごとの固有値 λ_k・λ_k ÷ λ_max・右辺の射影 β_k・増分 |β_k| ÷ λ_k・擬似逆が比べた δ_k・
//! 受理の側が比べる δ_k・この枝が捨てたかどうかと、その細分の Σλ_n と行ごとの δ_i である。
//! `relative_origin_discard`から分けているのは、あちらが600刻みの分類と退避を綴る工程であり、こちらが数細分を
//! 向き1本ずつ開く工程だからである(段階A3の`noise_floor_discard`と`discarded_direction_detail`と同じ分け方である)。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 基準原点の向きの内訳 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::substep_record::許容差依存の細分の記録;
