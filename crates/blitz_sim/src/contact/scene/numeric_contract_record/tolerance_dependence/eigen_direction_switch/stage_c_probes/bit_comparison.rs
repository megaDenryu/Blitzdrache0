//! Issue #103の段階Cの第3手の計器が使う、単精度の並びをビット列で突き合わせる工程(親の2026-09-13の指示)。
//! 値の等値比較(`==`)で突き合わせない理由は2つある。零と負の零は値として等しいがビット列が違い、その違いは
//! 以後の演算で意味を持つ。もう1つは、違ったときに「どれだけ違うか」を刻みの数で言いたいためである。
//! 刻みの差は、単精度を符号つきの整数の順序へ写してから引いた値であり、2つの値のあいだに表現できる値が
//! 何個あるかを表す。1なら隣り合う2つの値である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

/// 2つの単精度の並びのビット列を突き合わせた綴り。全部のビットが同じなら「一致」である。
pub(super) fn 単精度の並びを突き合わせる(左: &[f32], 右: &[f32]) -> String {
    let 違い: Vec<String> = 左
        .iter()
        .zip(右)
        .enumerate()
        .filter(|(_, (左の値, 右の値))| 左の値.to_bits() != 右の値.to_bits())
        .map(|(番号, (左の値, 右の値))| 一成分の違いを綴る(番号, *左の値, *右の値))
        .collect();
    if 違い.is_empty() {
        "一致".to_owned()
    } else {
        format!("違う({}成分)。{}", 違い.len(), 違い.join(" / "))
    }
}

/// 単精度の並びを、10進と16進のビット列の両方で綴る。
pub(super) fn 単精度の並びを綴る(並び: &[f32]) -> String {
    並び
        .iter()
        .enumerate()
        .map(|(番号, 値)| format!("成分{番号}={値:.9e}(0x{:08x})", 値.to_bits()))
        .collect::<Vec<_>>()
        .join(" ")
}

fn 一成分の違いを綴る(番号: usize, 左: f32, 右: f32) -> String {
    format!(
        "成分{番号}: 左={左:.9e}(0x{:08x}) 右={右:.9e}(0x{:08x}) 刻みの差={}",
        左.to_bits(),
        右.to_bits(),
        刻みの差(左, 右)
    )
}

// 2つの単精度のあいだに在る表現できる値の数。単精度を符号つきの整数の順序へ写して引く。
fn 刻みの差(左: f32, 右: f32) -> i64 {
    (順序づけた整数(左) - 順序づけた整数(右)).abs()
}

fn 順序づけた整数(値: f32) -> i64 {
    let ビット = 値.to_bits();
    let 大きさ = i64::from(ビット & 0x7fff_ffff);
    if ビット & 0x8000_0000 == 0 { 大きさ } else { -大きさ }
}
