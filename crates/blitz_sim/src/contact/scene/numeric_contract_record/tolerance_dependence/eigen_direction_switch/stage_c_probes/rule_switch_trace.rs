const 綴る細分の本数: usize = 6;

/// 細分の番号で当てる判定を決めながら進む1本の走行。
struct 判定を細分ごとに決める走行 {
    名前: &'static str,
    場面: 一つの箱と静的な直方体の場面,
    代わりの捨て方を当てる細分の数: usize, // 0なら素の本番、1なら細分0だけ、綴る本数以上なら毎細分
}

impl 判定を細分ごとに決める走行 {
    fn 一細分進めて綴る(&mut self, 見出し: &str, 番号: usize, 条件: &坂の場面の条件) {
        let 代わりを当てるか = 番号 < self.代わりの捨て方を当てる細分の数;
        self.場面.試験の許容差の当て方 = if 代わりを当てるか {
            捨て方を当てた適用規則(代表の代わりの捨て方())
        } else {
            試験の許容差の当て方::本番と同じ当て方()
        };
        let 当て方の綴り = if 代わりを当てるか { "代わりの捨て方" } else { "本番" };
        let 記録 = self.場面.記録しながら一細分進める(番号, 条件, true);
        let 比 = 記録.反復ごと.first().map_or(0.0, |反復| 反復.円錐の比());
        let Some(内訳) = 記録.入口.as_ref().and_then(|入口| 入口.一倍の内訳.as_ref()) else {
            println!(
                "  T [{見出し}] 細分{番号} {} 当てた判定={当て方の綴り} 粘着の候補が定まらず内訳が無い",
                self.名前
            );
            return;
        };
        let 本番の規則なら捨てる本数 = 内訳.固有の向きごと.iter().filter(|向き| 向き.本番の判定が捨てるか).count();
        println!(
            "  T [{見出し}] 細分{番号} {} 当てた判定={当て方の綴り} 向き={}本 偽の固有値で捨てた={}本 この求解が右辺の判定で捨てた={}本 本番の規則なら捨てる={本番の規則なら捨てる本数}本 解いた={}本 反復零の比={比:.12}",
            self.名前,
            内訳.固有の向きごと.len(),
            内訳.捨てた向きの数(擬似逆が固有の向きを捨てた理由::偽の固有値),
            内訳.捨てた向きの数(擬似逆が固有の向きを捨てた理由::右辺が許容差の内側),
            内訳.捨てた向きの数(擬似逆が固有の向きを捨てた理由::捨てていない)
        );
    }
}

fn 一つの回しの三本を綴る(鉛直軸まわりの回しの度: f32) {
    let 場合 = 細分十六本の場合(鉛直軸まわりの回しの度);
    let 条件 = 場合.坂の場面の条件を組む();
    let 見出し = format!("回し{鉛直軸まわりの回しの度}度");
    let 本番 = 試験の許容差の当て方::本番と同じ当て方();
    let mut 三本 = [
        判定を細分ごとに決める走行 {
            名前: "素の本番",
            場面: 場合.場面を当て方で組む(本番),
            代わりの捨て方を当てる細分の数: 0,
        },
        判定を細分ごとに決める走行 {
            名前: "変種_細分零だけ代わり",
            場面: 場合.場面を当て方で組む(本番),
            代わりの捨て方を当てる細分の数: 1,
        },
        判定を細分ごとに決める走行 {
            名前: "本命_毎細分代わり",
            場面: 場合.場面を当て方で組む(本番),
            代わりの捨て方を当てる細分の数: 綴る細分の本数,
        },
    ];
    println!(
        "[{見出し}] 細分16本の正接{傾きの正接} 判定の差し替えを細分0から細分{}まで追う",
        綴る細分の本数 - 1
    );
    for 番号 in 0..綴る細分の本数 {
        for 走行 in &mut 三本 {
            走行.一細分進めて綴る(&見出し, 番号, &条件);
        }
    }
}

