//! Issue #103の段階Cの第8手の計器(親の2026-09-13の指示)。3本の走行を細分0から細分5まで並べ、**その細分で実際に
//! 当てた判定**と、その求解が捨てた向きの本数の内訳と、反復零の後の円錐の比を12桁で綴る。
//! 3本は、素の本番(毎細分とも本番)・変種(細分0だけ代わりの捨て方)・本命(毎細分とも代わりの捨て方)である。
//! これが要るのは、第7手の変種の細分1の差が、本命の細分1の差と綴った7桁とも同一(+3.200510e-6)であるためである。
//! 細分1で本命は代わりの捨て方を当て、変種は本番を当てているのに、出力が同じ桁まで一致している。
//! 内訳には「この求解が実際に捨てた本数」に加えて「同じ配置へ本番の規則を当てたときに捨てる本数」も綴る。
//! 2つを並べると、その細分で2つの規則の答えが分かれるかどうかが1行で読める。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 判定の差し替えの追跡 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

