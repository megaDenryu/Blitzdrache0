//! Issue #103の段階A2の追補。候補(α)と候補(ζ)が滑走へ移る細分の手前で、その連立の固有の向きを1本ずつ綴る計器
//! (親の2026-09-12の指示)。綴るのは、向きごとの固有値 λ_k・最大の固有値に対する比 λ_k ÷ λ_max・右辺の射影 β_k・
//! 解いたときの増分 |β_k| ÷ λ_k・受理の側の許容差の射影 δ_k と、本番の形ならその向きを「右辺が許容差の内側」として
//! 捨てていたか(|β_k| ≤ δ_k か)である。あわせて、その細分の反復0の後の Σλ_n と、行ごとの δ_i を綴る。
//! 候補(α)は擬似逆へ渡す許容差を零にするため、内訳の「許容差の射影」は零になる。捨てるかどうかの判定に使えるのは
//! 受理の側の許容差の射影であり、そちらは本番の δ_i から組んだ値である。
//! `candidate_axes`から分けているのは、あちらが600刻みの分類と退避を綴る工程であり、こちらが滑走の手前の数細分を
//! 向き1本ずつ開く工程だからである。合否は判定しない。
//! 実行は `cargo test -p blitz_sim --release 捨てた向きの内訳 -- --ignored --nocapture` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

