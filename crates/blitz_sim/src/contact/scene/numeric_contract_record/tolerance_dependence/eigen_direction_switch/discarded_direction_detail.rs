// 1つの適用規則で細分を進め、窓の細分だけ固有の向きを1本ずつ綴る。
fn 一つの適用規則の窓を綴る(見出し: &str, 適用規則: 試験の許容差の当て方, 窓: (usize, usize)) {
    let 場合 = 遠方の正接零点五八の場合();
    let 条件 = 場合.坂の場面の条件を組む();
    let mut 場面 = 場合.場面を当て方で組む(適用規則);
    println!("[{見出し}] 細分{}〜{} の固有の向きの内訳", 窓.0, 窓.1);
    for 番号 in 0..=窓.1 {
        let 窓の中か = 番号 >= 窓.0;
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, 窓の中か);
        if 窓の中か {
            一細分の向きを綴る(番号, &記録);
        }
    }
}

// 細分1本の Σλ_n と行ごとの δ_i と、固有の向きごとの量を綴る。
fn 一細分の向きを綴る(番号: usize, 記録: &許容差依存の細分の記録) {
    let 反復零の法線の乗数の合計 = 記録.反復ごと.first().map_or(0.0, |反復| 反復.法線の乗数の合計);
    let Some(内訳) = 記録.入口.as_ref().and_then(|入口| 入口.一倍の内訳.as_ref()) else {
        println!(
            "  I 細分{番号} 粘着の候補が定まらず Σλ_n(反復0後)={反復零の法線の乗数の合計:.4e} 滑走中={}",
            記録.滑走中か()
        );
        return;
    };
    let λ_max = 内訳.固有の向きごと.iter().map(|向き| 向き.固有値).fold(0.0, f32::max);
    println!(
        "  I 細分{番号} 有効集合={} 行数={} Σλ_n(反復0後)={反復零の法線の乗数の合計:.4e} λ_max={λ_max:.4e} δ_i={:?}",
        内訳.有効集合の綴り(),
        内訳.固有の向きごと.len(),
        内訳.行ごとの解けたと見なす許容差.iter().map(|δ| format!("{δ:.3e}")).collect::<Vec<_>>()
    );
    for (k, 向き) in 内訳.固有の向きごと.iter().enumerate() {
        一つの向きを綴る(
            番号,
            k,
            向き.固有値,
            λ_max,
            向き.右辺の射影,
            向き.受理の許容差の射影,
            反復零の法線の乗数の合計,
        );
    }
    let 小さい向きの本数 = 内訳
        .固有の向きごと
        .iter()
        .filter(|向き| 向き.固有値 <= λ_max * 小さい向きと読む比)
        .count();
    println!("  I 細分{番号} λ_k ≤ λ_max ÷ 100 の向き={小さい向きの本数}本");
}

// λ_max に対して小さいと読む比。親の指示の「λ_max の1/100以下」である。
const 小さい向きと読む比: f32 = 0.01;

fn 一つの向きを綴る(番号: usize, k: usize, λ: f32, λ_max: f32, β: f32, δ_k: f32, σλ_n: f64) {
    let 増分 = if λ > 0.0 { (β / λ).abs() } else { 0.0 };
    println!(
        "    I 細分{番号} 向き{k} λ={λ:.4e} λ/λ_max={:.4e} β={β:+.4e} |β|={:.4e} 増分=|β|/λ={増分:.4e} δ_k(受理)={δ_k:.4e} 本番なら捨てる={} 増分/Σλ_n={:.4}",
        if λ_max > 0.0 { λ / λ_max } else { 0.0 },
        β.abs(),
        β.abs() <= δ_k,
        if σλ_n > 0.0 { f64::from(増分) / σλ_n } else { 0.0 }
    );
}

