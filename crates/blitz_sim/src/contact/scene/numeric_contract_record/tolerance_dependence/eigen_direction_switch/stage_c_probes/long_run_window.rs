//! Issue #103の段階Cの第5手の計器(親の2026-09-13の指示)。**本番の適用規則だけ**で2本走らせ、片方の初期の姿勢へ
//! 単精度の1刻みの摂動を入れて、9600細分(600刻み)まで進める。代わりの捨て方は1本も走らせない。
//! これが答えるのは「本番はなぜ9600細分のあいだ1度も円錐を超えないのか」である。摂動した本番が数百から数千細分で
//! 超えるなら、超過は捨て方に依らない。超えないなら、代わりの捨て方が名指しされる。どちらでも現在地が確定する。
//! 摂動の大きさを指定しないのは、単精度の刻みが値の大きさに比例し、指定した角が姿勢へ入るとは限らないためである。
//! 計器は実際に入った量(前後のビット列と、角に直した量)を綴る。
//! 綴る量を絞るのは、9600細分の全部を出すと読めない量になるためである。差が過去の最大を更新した細分と、
//! どちらかが円錐を超えた細分だけを綴り、最後に要約を出す。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 一刻みの摂動の長い走行 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

