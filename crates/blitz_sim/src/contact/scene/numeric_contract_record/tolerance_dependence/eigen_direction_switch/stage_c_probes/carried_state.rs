//! Issue #103の段階Cの第3手の計器が読む、細分の終わりに次の細分へ持ち越される剛体の状態(親の2026-09-13の指示)。
//! 持ち越されるのは、場面が細分をまたいで保つ4つ(重心の二段の位置・姿勢・並進速度・角速度)と、接触の履歴の項目である。
//! 接触拘束のバッチは細分ごとに組み直されるため持ち越されない。錨と前の細分の接触法線は履歴の項目が運ぶ。
//! 重心の位置を粗い位置と細かい位置へ分けて綴らないのは、その2つを分けて読む口が`blitz_math`のモジュールの内側に
//! 閉じており、このクレートから呼べないためである。代わりに、2つの走行の位置を二段のまま引いた差を綴る。
//! この差は、粗い位置どうしと細かい位置どうしの差から組むため、和を単精度へ畳んだ値の差より細かい。
//! 姿勢の4成分は`境界用xyzw配列`から読む。姿勢の成分をビット列で比べる口がほかに無いためである。
//! 速度と角速度は座標系と単位を持つ型のまま持ち、ビット列を比べる直前に成分の並びへ写す。単精度の3つ組を宣言すると
//! `cargo xtask conform` が落とすためであり、その検査は剛体の状態を裸の3つ組で持たせないために置かれている。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use blitz_math::{ワールド, 二段の位置, 角速度, 速度};

use super::bit_comparison::{単精度の並びを突き合わせる, 単精度の並びを綴る};
use crate::contact::history::剛体と静的世界の接触の履歴の項目;
use crate::contact::scene::substep_harness::一つの箱と静的な直方体の場面;

/// 細分の終わりに次の細分へ持ち越される状態。
pub(super) struct 細分の終わりに持ち越される状態 {
    重心の二段の位置: 二段の位置<ワールド>,
    姿勢の四成分: [f32; 4],
    並進速度: 速度<ワールド>,
    角速度: 角速度<ワールド>,
    履歴の項目: Vec<剛体と静的世界の接触の履歴の項目>,
}

impl 細分の終わりに持ち越される状態 {
    pub(super) fn 場面から読む(場面: &一つの箱と静的な直方体の場面) -> Self {
        let 速度 = 場面.箱の運動状態.並進速度();
        let 角速度 = 場面.箱の運動状態.角速度();
        Self {
            重心の二段の位置: 場面.箱の配置.重心の位置(),
            姿勢の四成分: 場面.箱の配置.姿勢().境界用xyzw配列(),
            並進速度: 速度,
            角速度,
            履歴の項目: 場面.履歴.項目一覧().to_vec(),
        }
    }

    /// 相手の状態と項目ごとに突き合わせて綴る。
    pub(super) fn 相手と突き合わせて綴る(&self, 見出し: &str, 相手: &Self) {
        let 位置の差 = self.重心の二段の位置 - 相手.重心の二段の位置;
        let 差の成分の並び = vec![位置の差.x().値(), 位置の差.y().値(), 位置の差.z().値()];
        println!(
            "  S [{見出し}] 重心の二段の位置: {} 二段のまま引いた差の3成分: {}",
            if self.重心の二段の位置 == 相手.重心の二段の位置 {
                "一致"
            } else {
                "違う"
            },
            単精度の並びを綴る(&差の成分の並び)
        );
        println!(
            "  S [{見出し}] 姿勢の4成分: {}",
            単精度の並びを突き合わせる(&self.姿勢の四成分, &相手.姿勢の四成分)
        );
        println!(
            "  S [{見出し}] 並進速度の3成分: {}",
            単精度の並びを突き合わせる(&速度の成分の並び(self.並進速度), &速度の成分の並び(相手.並進速度))
        );
        println!(
            "  S [{見出し}] 角速度の3成分: {}",
            単精度の並びを突き合わせる(&角速度の成分の並び(self.角速度), &角速度の成分の並び(相手.角速度))
        );
        self.履歴を突き合わせて綴る(見出し, 相手);
    }

    // 接触の履歴の項目(錨と前の細分の接触法線)を1件ずつ突き合わせる。
    fn 履歴を突き合わせて綴る(&self, 見出し: &str, 相手: &Self) {
        println!(
            "  S [{見出し}] 履歴の項目数: 左={}件 右={}件",
            self.履歴の項目.len(),
            相手.履歴の項目.len()
        );
        for (番号, (左, 右)) in self.履歴の項目.iter().zip(&相手.履歴の項目).enumerate() {
            if 左 == 右 {
                println!("  S [{見出し}] 履歴の項目{番号}(錨と前の細分の接触法線): 一致");
            } else {
                println!("  S [{見出し}] 履歴の項目{番号}: 違う。左={左:?} 右={右:?}");
            }
        }
    }
}

// 速度の3成分を、ビット列の突き合わせが読む並びへ写す。
fn 速度の成分の並び(速度: 速度<ワールド>) -> Vec<f32> {
    vec![速度.x().値(), 速度.y().値(), 速度.z().値()]
}

// 角速度の3成分を、同じ形の並びへ写す。
fn 角速度の成分の並び(角速度: 角速度<ワールド>) -> Vec<f32> {
    vec![角速度.x().値(), 角速度.y().値(), 角速度.z().値()]
}
