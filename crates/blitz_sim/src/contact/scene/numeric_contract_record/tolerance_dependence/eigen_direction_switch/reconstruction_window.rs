//! Issue #103の段階Cの第4手の計器(親の2026-09-13の指示)。細分0を本番と代わりの捨て方で進め、**速度の再構成の前と後を
//! 分けて**綴る。前は、前の状態から確定した配置までの変化(位置の変化と、姿勢の変化を回る角で表したもの)であり、
//! 後は、その変化を刻み幅で割って出た並進速度と角速度である。速度段階を通した後の値は第3手の計器が綴る。
//! あわせて、走行に依らない量として、姿勢の成分の1刻みと位置の変化の成分の1刻みが速度でいくつになるかを綴る。
//! これが要るのは、第3手が「姿勢が1刻み違うだけで角速度が61パーセント違う」ことを測った一方、その61パーセントが
//! 表現の刻みを刻み幅で割った量に張り付いているかを測っていないためである。張り付いているなら、増幅しているのは
//! 連立でも時間の積分でもなく、速度の再構成が配置の表現の刻みを速度へ写す段である。
//! 再構成は本番と同じ口(`前の状態::確定した配置から速度を再構成する`)を呼び、式を1つも書き写さない。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 速度の再構成の床 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

