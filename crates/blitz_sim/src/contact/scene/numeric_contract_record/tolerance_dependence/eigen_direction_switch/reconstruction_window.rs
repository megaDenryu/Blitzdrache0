// 1本の走行を細分0だけ進め、前の状態と確定した配置と、再構成した速度と角速度を返す。
struct 細分零の再構成の読み取り {
    位置の変化: Vec<f32>,
    回る角: f32,
    並進速度: Vec<f32>,
    角速度: Vec<f32>,
    確定した姿勢の四成分: [f32; 4],
}

fn 細分零を進めて再構成を読む(
    場面: &mut 一つの箱と静的な直方体の場面, 条件: &坂の場面の条件
) -> 細分零の再構成の読み取り {
    let 前 = 前の状態::配置から保存する(&場面.箱の配置);
    let _ = 場面.記録しながら一細分進める(0, 条件, false);
    let 確定: 配置 = 場面.箱の配置;
    let 変化 = 確定.重心の位置() - 前.重心の位置();
    let 回転 = 確定.姿勢().前の姿勢からの微小回転(前.姿勢());
    let 運動状態 = 前.確定した配置から速度を再構成する(&確定, 場面.刻み幅);
    let 速度 = 運動状態.並進速度();
    let 角速度 = 運動状態.角速度();
    細分零の再構成の読み取り {
        位置の変化: vec![変化.x().値(), 変化.y().値(), 変化.z().値()],
        回る角: 回転.長さ().値(),
        並進速度: vec![速度.x().値(), 速度.y().値(), 速度.z().値()],
        角速度: vec![角速度.x().値(), 角速度.y().値(), 角速度.z().値()],
        確定した姿勢の四成分: 確定.姿勢().境界用xyzw配列(),
    }
}

fn 差の並び(左: &[f32], 右: &[f32]) -> Vec<f32> {
    左.iter().zip(右).map(|(左の値, 右の値)| 左の値 - 右の値).collect()
}

fn 一つの回しの再構成を綴る(鉛直軸まわりの回しの度: f32) {
    let 場合 = 細分十六本の場合(鉛直軸まわりの回しの度);
    let 条件 = 場合.坂の場面の条件を組む();
    let 見出し = format!("回し{鉛直軸まわりの回しの度}度");
    let mut 本番の場面 = 場合.場面を当て方で組む(試験の許容差の当て方::本番と同じ当て方());
    let mut 代わりの場面 = 場合.場面を当て方で組む(捨て方を当てた適用規則(代表の代わりの捨て方()));
    let 刻み幅の秒 = 本番の場面.刻み幅.秒().値();
    println!("[{見出し}] 細分16本の正接{傾きの正接} 刻み幅={刻み幅の秒:.6e}秒 速度の再構成の前と後");
    let 本番 = 細分零を進めて再構成を読む(&mut 本番の場面, &条件);
    let 代わり = 細分零を進めて再構成を読む(&mut 代わりの場面, &条件);
    二本の読み取りを綴る(&見出し, 刻み幅の秒, &本番, &代わり);
}

fn 二本の読み取りを綴る(
    見出し: &str, 刻み幅の秒: f32, 本番: &細分零の再構成の読み取り, 代わり: &細分零の再構成の読み取り
) {
    println!(
        "  R [{見出し}] 再構成の前 位置の変化の差: {}",
        成分ごとの量を綴る(&差の並び(&本番.位置の変化, &代わり.位置の変化))
    );
    println!(
        "  R [{見出し}] 再構成の前 回る角: 本番={:.6e} 代わり={:.6e} 差={:+.6e}",
        本番.回る角,
        代わり.回る角,
        本番.回る角 - 代わり.回る角
    );
    println!(
        "  R [{見出し}] 再構成の後 並進速度の差: {}",
        成分ごとの量を綴る(&差の並び(&本番.並進速度, &代わり.並進速度))
    );
    println!(
        "  R [{見出し}] 再構成の後 角速度: 本番={} 代わり={}",
        成分ごとの量を綴る(&本番.角速度),
        成分ごとの量を綴る(&代わり.角速度)
    );
    println!(
        "  R [{見出し}] 再構成の後 角速度の差: {}",
        成分ごとの量を綴る(&差の並び(&本番.角速度, &代わり.角速度))
    );
    let 姿勢の床: Vec<f32> = 本番
        .確定した姿勢の四成分
        .iter()
        .map(|成分| 姿勢の一刻みが角速度へ写る量(*成分, 刻み幅の秒))
        .collect();
    println!("  R [{見出し}] 姿勢の成分の1刻みが角速度へ写る量: {}", 成分ごとの量を綴る(&姿勢の床));
    let 位置の床: Vec<f32> = 本番
        .位置の変化
        .iter()
        .map(|成分| 位置の変化の一刻みが速度へ写る量(*成分, 刻み幅の秒))
        .collect();
    println!(
        "  R [{見出し}] 位置の変化の成分の1刻みが並進速度へ写る量: {}",
        成分ごとの量を綴る(&位置の床)
    );
    let 床の最大 = 姿勢の床.iter().fold(0.0, |最大: f32, 値| 最大.max(*値));
    let 角速度の差の最大 = 差の並び(&本番.角速度, &代わり.角速度)
        .iter()
        .fold(0.0, |最大: f32, 値| 最大.max(値.abs()));
    println!(
        "  R [{見出し}] 角速度の差の最大 ÷ 姿勢の1刻みが角速度へ写る量の最大 = {:.4}",
        角速度の差の最大 / 床の最大
    );
}

