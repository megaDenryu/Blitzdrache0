//! Issue #103の段階A5の計測11と計測12。緩い坂(正接0.30)で、偽の固有値の下限のすぐ上に居る固有の向きが、下限から
//! どれだけ離れているかを綴る計器(親の2026-09-12の指示。副官の予測を確かめる)。
//! 計測11は箱の半分の長さを 0.25・0.5・1.0 と振り、計測12は鉛直軸まわりの回しを40度から50度まで1度刻みで振る。
//! これが要るのは、段階A5の計測4が「回し45度の床は箱の腕にも姿勢にも滑らかに依らず、45度と腕0.5の組だけが跳ねる」
//! ことを測ったためである。副官の予測は「跳ねる組だけが、最小の相対固有値と偽の固有値の下限の比が1に近い」である。
//! 当たるなら、跳ねは閾値をまたぐかどうかの現象であり、丸めでも姿勢の連続な機構でもないことが確定する。
//! 綴るのは細分ごとに1行である。偽の固有値の下限より上に居る向きのうち相対固有値が最小のものと、その相対固有値を
//! 下限の相対値で割った比と、その向きが右辺の判定で捨てられたかである。比が1に近い向きは、細分ごとの単精度の
//! 読みの揺れ(表44が測った相対で 1.5e-6 の桁)で下限をまたぐ。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 下限のすぐ上の向きの余裕 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

