const 綴る細分の本数: usize = 64;

// 偽の固有値の下限より上に居る向きのうち、相対固有値が最小のものの番号。1本も無ければ無しである。
fn 下限のすぐ上の向きの番号(内訳: &単精度の解の内訳) -> Option<usize> {
    (0..内訳.固有の向きごと.len())
        .filter(|k| 内訳.固有の向きごと[*k].固有値 > 内訳.偽の固有値の下限)
        .min_by(|左, 右| 内訳.固有の向きごと[*左].固有値.total_cmp(&内訳.固有の向きごと[*右].固有値))
}

fn 一つの場面の余裕を綴る(場合: &許容差依存の診断の場合) {
    let 条件 = 場合.坂の場面の条件を組む();
    let mut 場面 = 場合.場面を当て方で組む(試験の許容差の当て方::本番と同じ当て方());
    let (mut 比の最小, mut 比の最大, mut 捨てられた細分) = (f32::INFINITY, 0.0f32, 0);
    for 番号 in 0..綴る細分の本数 {
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, true);
        let Some(内訳) = 記録.入口.as_ref().and_then(|入口| 入口.一倍の内訳.as_ref()) else {
            continue;
        };
        let Some(k) = 下限のすぐ上の向きの番号(内訳) else {
            continue;
        };
        let 相対固有値 = 内訳.固有の向きごと[k].固有値 / 内訳.最大の固有値;
        let 下限の相対値 = 内訳.偽の固有値の下限 / 内訳.最大の固有値;
        let 比 = 相対固有値 / 下限の相対値;
        比の最小 = 比の最小.min(比);
        比の最大 = 比の最大.max(比);
        捨てられた細分 += usize::from(内訳.固有の向きごと[k].捨てた理由 == 擬似逆が固有の向きを捨てた理由::右辺が許容差の内側);
    }
    println!(
        "  M [{}] 下限のすぐ上の向きの相対固有値 ÷ 下限の相対値: 最小={比の最小:.4e} 最大={比の最大:.4e} その向きが右辺の判定で捨てられた細分={捨てられた細分}本 / {綴る細分の本数}本",
        場合.見出し()
    );
}

