//! Issue #103の段階Cの第4手の計器が読む、速度の再構成の量子化の床(親の2026-09-13の指示)。
//! 速度の再構成は v = (x − x_前) ÷ h と ω = 2·vec(q ⊗ q_前⁻¹) ÷ h であり(判断9)、どちらも単精度で持った配置の差を
//! 刻み幅で割る。刻み幅が 1e-3 秒の桁であるから、配置の表現の1刻みは速度では 1e3 倍の量になる。
//! この型が答えるのは、姿勢の成分の1刻みと位置の変化の成分の1刻みが、角速度と並進速度でいくつになるかである。
//! 走行に依らない量であり、2つの走行の速度の差と並べて読むために要る。
//! 姿勢の成分が1刻み動いたときに回る角をおよそ 2×1刻み とするのは、微小な回転として読む式 ω = 2·vec(q) の係数である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

/// 単精度の値の隣の値までの隔たり(1刻み)。零のときは正の側の最小の正規化されていない値である。
pub(super) fn 単精度の一刻み(値: f32) -> f32 {
    let 大きさのビット = 値.abs().to_bits();
    f32::from_bits(大きさのビット + 1) - 値.abs()
}

/// 姿勢の成分が1刻み動いたときに角速度へ写る量 2×1刻み ÷ h。
pub(super) fn 姿勢の一刻みが角速度へ写る量(姿勢の成分: f32, 刻み幅の秒: f32) -> f32 {
    2.0 * 単精度の一刻み(姿勢の成分) / 刻み幅の秒
}

/// 位置の変化の成分が1刻み動いたときに並進速度へ写る量 1刻み ÷ h。
pub(super) fn 位置の変化の一刻みが速度へ写る量(位置の変化の成分: f32, 刻み幅の秒: f32) -> f32 {
    単精度の一刻み(位置の変化の成分) / 刻み幅の秒
}

/// 成分ごとの量を、成分の番号を添えて綴る。
pub(super) fn 成分ごとの量を綴る(並び: &[f32]) -> String {
    並び
        .iter()
        .enumerate()
        .map(|(番号, 値)| format!("成分{番号}={値:.6e}"))
        .collect::<Vec<_>>()
        .join(" ")
}
