//! Issue #103の段階Bの計器が綴る、1つの求解の中身の行(親の2026-09-13の指示)。
//! 綴るのは4段である。向きごと(固有値・相対固有値・右辺の射影・向きへ積み上げた許容差・本番と枝の採否・増分・
//! その向きだけを解いた Jᵀ Δλ が剛体へ入れる並進と回転)、行ごと(δ_i・元の行空間の残差・乗数の増分)、
//! 反復ごと(法線の乗数の合計・接線の合力の大きさ・円錐の比)、接触点ごと(特徴の識別・錨からの接線変位・錨の置き直し・滑走中)である。
//! 円錐の判定が滑走の瞬間に読んだ量と、粘着の候補が解けなかった集合の読み取りも、同じ細分の行として綴る。
//! 段階A6の追補で、見出しが規則を言わず行の出る順でしか読めない事故が起きたため、どの行にも細分と適用規則の名前を入れる。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::substep_record::許容差依存の細分の記録;
use crate::contact::normal_tangential_system::単精度の解の内訳;

// 枝(相対固有値が小さい向きを捨てる)が、この向きを捨てるか。偽の固有値で落ちる向きはどちらの規則でも捨てる。
fn 枝の判定が捨てるか(内訳: &単精度の解の内訳, 固有値: f32, 最大の固有値への相対比: f32) -> bool {
    固有値 > 内訳.偽の固有値の下限 && 内訳.最大の固有値 > 0.0 && 固有値 / 内訳.最大の固有値 <= 最大の固有値への相対比
}

/// 固有の向きごとの採否と増分と、その向きが剛体へ入れる補正を綴る。
pub(super) fn 向きごとを綴る(番号: usize, 規則: &str, 内訳: &単精度の解の内訳, 最大の固有値への相対比: f32) {
    for (k, 向き) in 内訳.固有の向きごと.iter().enumerate() {
        let 増分 = if 向き.固有値 > 0.0 {
            (向き.右辺の射影 / 向き.固有値).abs()
        } else {
            0.0
        };
        println!(
            "    Y 細分{番号} [{規則}] 向き{k} λ={:.4e} λ/λ_max={:.4e} |β|={:.4e} δ_k={:.4e} 本番が捨てる={} 枝が捨てる={} この求解の理由={:?} 増分={増分:.4e} {}",
            向き.固有値,
            向き.固有値 / 内訳.最大の固有値,
            向き.右辺の射影.abs(),
            向き.許容差の射影,
            向き.本番の判定が捨てるか,
            枝の判定が捨てるか(内訳, 向き.固有値, 最大の固有値への相対比),
            向き.捨てた理由,
            向き.剛体へ入る補正.綴り()
        );
    }
}

/// 行ごとの δ_i・元の行空間の残差・乗数の増分を綴る。
pub(super) fn 行ごとを綴る(番号: usize, 規則: &str, 内訳: &単精度の解の内訳) {
    for 行 in 0..内訳.行ごとの残差.len() {
        let 種別 = if 行 < 内訳.法線の行の数 { "法線" } else { "接線" };
        println!(
            "    R 細分{番号} [{規則}] {種別}の行{行} δ_i={:.4e} 残差={:.4e} 乗数の増分={:.4e}",
            内訳.行ごとの解けたと見なす許容差[行], 内訳.行ごとの残差[行], 内訳.行ごとの乗数の増分[行]
        );
    }
}

/// 反復ごとの法線の乗数の合計・接線の合力の大きさ・円錐の比を綴る。
pub(super) fn 反復ごとを綴る(規則: &str, 記録: &許容差依存の細分の記録) {
    for (反復, 読み取り) in 記録.反復ごと.iter().enumerate() {
        println!(
            "    C 細分{} [{規則}] 反復{反復} 法線の乗数の合計={:.6e} 接線の合力の大きさ={:.6e} 円錐の比={:.6} 滑走中の点={}個 解けなかった集合={}個",
            記録.番号,
            読み取り.法線の乗数の合計,
            読み取り.接線の合力の大きさ,
            読み取り.円錐の比(),
            読み取り.滑走中の点の数,
            読み取り.解けなかった集合の数
        );
    }
}

/// 円錐を超えて滑走へ移った集合と、粘着の候補が解けなかった集合を綴る。滑走の瞬間に判定が読んだ比は、
/// 細分の終わりの反復ごとの読み取り(そちらは滑走へ移った後の値であり合力が零になる)では読めない。
pub(super) fn 判定が退けた集合を綴る(規則: &str, 記録: &許容差依存の細分の記録) {
    for (反復, 読み取り) in &記録.円錐を超えた集合 {
        println!("    B 細分{} [{規則}] 反復{反復} {}", 記録.番号, 読み取り.綴り());
    }
    for (反復, 読み取り) in &記録.解けなかった連立 {
        println!("    U 細分{} [{規則}] 反復{反復} {}", 記録.番号, 読み取り.綴り());
    }
}

/// 細分の終わりに接触点ごとから読んだ素性と解の状態を綴る。
pub(super) fn 接触点ごとを綴る(規則: &str, 記録: &許容差依存の細分の記録) {
    for (点, 読み取り) in 記録.終わりの接触点ごと.iter().enumerate() {
        println!("    E 細分{} [{規則}] 点{点} {}", 記録.番号, 読み取り.綴り());
    }
}
