//! Issue #103の段階Cの第1手の計器(親の2026-09-13の指示)。細分16本の正接0.55の坂を、同じ窓で3つの対として走らせる。
//! 対照1は本番と本番(同じ初期条件・同じ適用規則)、対照2は本番と姿勢だけを摂動した本番、本命は本番と代わりの捨て方である。
//! これが要るのは、段階Bが測った「差が細分2から3で 1e-3 の帯へ達し、その帯で振れる」という育ち方が、擬似逆の
//! 捨て方に由来するのか、2つの軌道が単に脱相関しただけなのかを、段階Bの計測が分けていないためである。
//! 対照1の差が全部の細分で厳密に零であることが、以後の計測が走行ごとの非決定性を測っていないことの根拠になる。
//! 対照2が本命と同じ育ち方をするなら、育ち方は捨て方に固有ではなく、雑音の水準の摂動一般の性質である。
//! 窓は細分0から、代わりの捨て方が最初に円錐を超える細分までであり、段階Bの窓と同じ決め方である。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 摂動の対照の窓 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::alternative_discard_record::{代表の代わりの捨て方, 捨て方を当てた適用規則};
use super::first_cone_crossing::{傾きの正接, 振る回しの度, 最初に滑走した細分を探す, 細分十六本の場合};
use super::paired_run::対にした二つの走行;
use super::posture_perturbation::{摂動の角のラジアン, 摂動を回す軸の綴り, 箱の姿勢を摂動で回す};
use crate::contact::normal_tangential_system::試験の許容差の当て方;

fn 一つの回しの三つの対を綴る(鉛直軸まわりの回しの度: f32) {
    let 場合 = 細分十六本の場合(鉛直軸まわりの回しの度);
    println!("[回し{鉛直軸まわりの回しの度}度] 細分16本の正接{傾きの正接} の摂動の対照の窓");
    let Some(窓の終わり) = 最初に滑走した細分を探す(&場合, 捨て方を当てた適用規則(代表の代わりの捨て方()))
    else {
        println!("  D 代わりの捨て方がこの姿勢で1本も滑走しなかった。窓が定まらない");
        return;
    };
    println!("  D 代わりの捨て方が最初に滑走した細分={窓の終わり}。窓は細分0から細分{窓の終わり}である");
    let 条件 = 場合.坂の場面の条件を組む();
    let 本番 = 試験の許容差の当て方::本番と同じ当て方();
    let mut 対照一 =
        対にした二つの走行::見出しと二本から組む("対照1_本番と本番", 場合.場面を当て方で組む(本番), 場合.場面を当て方で組む(本番));
    対照一.窓を細分ごとに綴る(&条件, 窓の終わり);
    let mut 摂動した場面 = 場合.場面を当て方で組む(本番);
    let 動かしたか = 箱の姿勢を摂動で回す(&mut 摂動した場面);
    println!(
        "  D 回し{鉛直軸まわりの回しの度}度 摂動={摂動の角のラジアン:.4e}ラジアン 軸={摂動を回す軸の綴り} {}",
        動かしたか.綴り()
    );
    let mut 対照二 =
        対にした二つの走行::見出しと二本から組む("対照2_本番と姿勢を摂動した本番", 場合.場面を当て方で組む(本番), 摂動した場面);
    対照二.窓を細分ごとに綴る(&条件, 窓の終わり);
    let mut 本命 = 対にした二つの走行::見出しと二本から組む(
        "本命_本番と代わりの捨て方",
        場合.場面を当て方で組む(本番),
        場合.場面を当て方で組む(捨て方を当てた適用規則(代表の代わりの捨て方())),
    );
    本命.窓を細分ごとに綴る(&条件, 窓の終わり);
}

