//! Issue #103の段階Cの第5手の計器が9600細分のあいだ溜める量(親の2026-09-13の指示)。
//! 9600細分の全部を綴ると読めない量になるため、この型が「差が過去の最大を更新した細分」だけを綴り、どちらかが
//! 円錐を超えた細分を全部綴り、最後に要約を1行出す。
//! 更新した細分だけを綴るのは、差が単調に育つのか、ある細分で跳ぶのかを、行の並びだけで読めるようにするためである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

/// 2本の走行を長く進めたあいだの、円錐の比の差と円錐の超過の溜まり。
pub(super) struct 長い走行の溜まり {
    見出し: String,
    差の大きさの最大: f64,
    超えた延べ数: usize,
    最初に超えた細分: Option<usize>,
}

impl 長い走行の溜まり {
    pub(super) fn 見出しから始める(見出し: String) -> Self {
        Self {
            見出し,
            差の大きさの最大: 0.0,
            超えた延べ数: 0,
            最初に超えた細分: None,
        }
    }

    /// 1細分の差を数える。過去の最大を更新したときだけ行を綴る。
    pub(super) fn 一細分の差を数える(&mut self, 番号: usize, 素の比: f64, 摂動した比: f64) {
        let 差 = 摂動した比 - 素の比;
        if 差.abs() <= self.差の大きさの最大 {
            return;
        }
        self.差の大きさの最大 = 差.abs();
        println!(
            "  L [{}] 細分{番号} 素の比={素の比:.9} 摂動した比={摂動した比:.9} 差={差:+.6e}(過去の最大を更新)",
            self.見出し
        );
    }

    /// 1細分の円錐の超過を数える。超えた側と綴りをそのまま出す。
    pub(super) fn 一細分の超過を数える(&mut self, 番号: usize, 走行: &str, 綴り: &str) {
        self.超えた延べ数 += 1;
        if self.最初に超えた細分.is_none() {
            self.最初に超えた細分 = Some(番号);
        }
        println!("  L [{}] 細分{番号} {走行} {綴り}", self.見出し);
    }

    /// 走り終えた後の要約。
    pub(super) fn 要約を綴る(&self, 進めた細分の本数: usize) {
        println!(
            "  L [{}] 要約 進めた細分={進めた細分の本数}本 差の大きさの最大={:.6e} 円錐を超えた延べ数={}件 最初に超えた細分={:?}",
            self.見出し, self.差の大きさの最大, self.超えた延べ数, self.最初に超えた細分
        );
    }
}
