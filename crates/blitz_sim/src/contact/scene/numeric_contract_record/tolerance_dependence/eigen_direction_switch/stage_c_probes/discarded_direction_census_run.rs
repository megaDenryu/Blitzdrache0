fn 一つの回しの捨てた向きを数える(鉛直軸まわりの回しの度: f32) {
    let 場合 = 細分十六本の場合(鉛直軸まわりの回しの度);
    let 条件 = 場合.坂の場面の条件を組む();
    let 細分の本数 = 走らせる刻みの数 * 場合.変更.一刻みの細分数();
    let mut 場面 = 場合.場面を当て方で組む(試験の許容差の当て方::本番と同じ当て方());
    let mut 集まり = 本番が右辺の判定で捨てた向きの集まり::零から始める();
    println!("[回し{鉛直軸まわりの回しの度}度] 細分16本の正接{傾きの正接} を本番だけで{細分の本数}細分進める");
    for 番号 in 0..細分の本数 {
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, true);
        if let Some(内訳) = 記録.入口.as_ref().and_then(|入口| 入口.一倍の内訳.as_ref()) {
            集まり.一細分の求解を数える(番号, 内訳);
        }
    }
    println!("  V [回し{鉛直軸まわりの回しの度}度] {}", 集まり.綴り());
}

