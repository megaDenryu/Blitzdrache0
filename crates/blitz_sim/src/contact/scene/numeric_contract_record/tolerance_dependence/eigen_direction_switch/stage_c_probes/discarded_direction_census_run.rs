//! 600刻み(9600細分)走らせ、細分ごとの第一反復の入口で、本番が右辺の判定で捨てている向きの3つ組を集める。
//! 3つ組は、固有値を最大の固有値で割った値・右辺の射影を向きへ積み上げた許容差で割った値・その向きを解いたと
//! 仮定したときに剛体へ入る並進と回転である。代わりの捨て方は1本も走らせない。
//! これが要るのは、段階Bの表93が円錐を超えた細分で見つけた形の向き(相対固有値が閾値のすぐ上で、右辺が許容差の
//! 内側で、剛体へ大きな並進を入れる向き)が、まれな事故なのか常時現れているのかを分けるためである。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 捨てた向きの出現頻度 -- --ignored --nocapture --test-threads=1` である。
