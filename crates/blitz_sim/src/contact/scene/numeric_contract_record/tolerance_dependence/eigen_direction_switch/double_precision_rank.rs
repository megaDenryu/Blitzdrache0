// 段階A2の追補が、偽の固有値の下限のすぐ上の向きを見つけた細分とその手前。
const 開く窓: (usize, usize) = (60, 66);

fn 相対値の並び<T: Copy + Into<f64>>(固有値: &[T]) -> String {
    let 最大 = 固有値.iter().fold(0.0f64, |最大, 値| 最大.max((*値).into()));
    if 最大 <= 0.0 {
        return "λ_maxが正でない".to_owned();
    }
    固有値
        .iter()
        .map(|値| format!("{:.3e}", (*値).into() / 最大))
        .collect::<Vec<_>>()
        .join(",")
}

// 細分1本の単精度と倍精度の相対値を並べる。
fn 一細分の階数を綴る(番号: usize, 記録: &許容差依存の細分の記録) {
    let Some(入口) = 記録.入口.as_ref() else {
        println!("  L 細分{番号} 入口を読んでいない");
        return;
    };
    println!("  L 細分{番号} 倍精度の相対値={}", 相対値の並び(&入口.倍精度の刻みの固有値));
    let Some(内訳) = 入口.一倍の内訳.as_ref() else {
        println!("  L 細分{番号} 単精度の粘着の候補が定まらず");
        return;
    };
    let 単精度: Vec<f32> = 内訳.固有の向きごと.iter().map(|向き| 向き.固有値).collect();
    println!(
        "  L 細分{番号} 有効集合={} 行数={} λ_max={:.4e} 偽の固有値の下限の相対値={:.3e} 単精度の相対値={}",
        内訳.有効集合の綴り(),
        単精度.len(),
        内訳.最大の固有値,
        内訳.偽の固有値の下限 / 内訳.最大の固有値,
        相対値の並び(&単精度)
    );
}

