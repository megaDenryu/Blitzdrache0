//! 分解し、固有値を最大の固有値で割った相対値を向きごとに並べる計器(親の2026-09-12の指示)。
//! 問いは1つである。単精度で λ ÷ λ_max が 2e-6 の桁に居た向きは、階数不足の向き(倍精度で 1e-15 の桁へ落ちる)か、
//! 実在する弱い拘束(倍精度でも 1e-6 の桁に留まる)か。行数8・剛体1つの自由度6であるから零の向きが2本なのは確定しており、
//! 3本目が在るかどうかがこの計測の問いである。前者なら、その向きを捨てる仕組みは階数の扱いであって許容差の問題ではない。
