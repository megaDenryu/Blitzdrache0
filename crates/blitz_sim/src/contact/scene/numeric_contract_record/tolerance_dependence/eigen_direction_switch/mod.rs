const 分類が分岐する細分: usize = 3341;
const 窓が分岐より前に覆う細分の本数: usize = 21;
const 窓が分岐より後に覆う細分の本数: usize = 4;

fn 遠方の正接零点五八の場合() -> 許容差依存の診断の場合 {
    許容差依存の診断の場合 {
        静止摩擦係数の値: 0.6,
        傾きの正接: 敵対の傾きの正接,
        鉛直軸まわりの回しの度: 0.0,
        許容差の比: 1.0,
        行への許容差の当て方: 接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする,
        変更: 段階A1の場面からの一つの変更::坂の面の法線の向きへ動かす {
            長さ: メートル::生成する(刻みを二倍にする長さ),
        },
    }
}

fn 窓の始まりの細分() -> usize {
    分類が分岐する細分 - 窓が分岐より前に覆う細分の本数
}

fn 窓の終わりの細分() -> usize {
    分類が分岐する細分 + 窓が分岐より後に覆う細分の本数
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 固有の向きの採否_遠方の正接零点五八を受理一倍と二倍の窓で読む() {
    for 比 in [1.0, 2.0] {
        let 当て方 =
            試験の許容差の当て方::本番と同じ当て方().受理の倍率を差し替える(解けたと見なす許容差の倍率::比から生成する(比));
        let 窓 = 細分を綴る窓::入口も読む {
            始まりの細分: 窓の始まりの細分(),
            終わりの細分: 窓の終わりの細分(),
        };
        一本の軌道を窓つきで綴る(&遠方の正接零点五八の場合(), 当て方, 窓);
    }
}

