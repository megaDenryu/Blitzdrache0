// 突き合わせる2方向。回し30度は細分0の円錐の比の差が厳密に零であり、細分0で分かれていないため外す。
const 突き合わせる回しの度: &[f32] = &[0.0, 45.0];

// 接触点ごとの滑走中の印と錨を置き直したかを、2つの走行で突き合わせる。
fn 接触点ごとの印を綴る(見出し: &str, 本番: &許容差依存の細分の記録, 代わり: &許容差依存の細分の記録) {
    for (点, (左, 右)) in 本番.終わりの接触点ごと.iter().zip(&代わり.終わりの接触点ごと).enumerate() {
        println!(
            "  S [{見出し}] 点{点} 特徴の識別={} 置き直した={}と{} 滑走中={}と{}",
            if 左.特徴の識別() == 右.特徴の識別() {
                "一致"
            } else {
                "違う"
            },
            左.錨を置き直したか(),
            右.錨を置き直したか(),
            左.滑走中か(),
            右.滑走中か()
        );
    }
}

fn 一つの回しの細分零の持ち越しを突き合わせる(鉛直軸まわりの回しの度: f32) {
    let 場合 = 細分十六本の場合(鉛直軸まわりの回しの度);
    let 条件 = 場合.坂の場面の条件を組む();
    let 見出し = format!("回し{鉛直軸まわりの回しの度}度");
    let mut 本番の場面 = 場合.場面を当て方で組む(試験の許容差の当て方::本番と同じ当て方());
    let mut 代わりの場面 = 場合.場面を当て方で組む(捨て方を当てた適用規則(代表の代わりの捨て方()));
    println!("[{見出し}] 細分16本の正接{傾きの正接} 細分0の終わりに持ち越される状態の突き合わせ");
    let 本番の細分零 = 本番の場面.記録しながら一細分進める(0, &条件, false);
    let 代わりの細分零 = 代わりの場面.記録しながら一細分進める(0, &条件, false);
    細分の終わりに持ち越される状態::場面から読む(&本番の場面)
        .相手と突き合わせて綴る(&見出し, &細分の終わりに持ち越される状態::場面から読む(&代わりの場面));
    接触点ごとの印を綴る(&見出し, &本番の細分零, &代わりの細分零);
    円錐の比を綴る(&見出し, 0, &本番の細分零, &代わりの細分零);
    let 本番の細分一 = 本番の場面.記録しながら一細分進める(1, &条件, false);
    let 代わりの細分一 = 代わりの場面.記録しながら一細分進める(1, &条件, false);
    円錐の比を綴る(&見出し, 1, &本番の細分一, &代わりの細分一);
}

// 錨からの接線変位の合計を、細分の入口・反復ごと・細分の終わりで綴る。
fn 接線変位の合計を綴る(見出し: &str, 番号: usize, 走行: &str, 記録: &許容差依存の細分の記録) {
    let 反復ごと: Vec<String> = 記録.反復ごと.iter().map(|反復| format!("{:.6e}", 反復.錨からの接線変位の合計)).collect();
    println!(
        "  A [{見出し}] 細分{番号} {走行} 入口のΣ|Δt|={:.6e} 反復ごとのΣ|Δt|=[{}] 終わりのΣ|Δt|={:.6e} δ_t={:.6e}",
        記録.入口の接線変位の合計,
        反復ごと.join(","),
        記録.終わりの接線変位の合計(),
        記録.接線の行の許容差
    );
}

fn 円錐の比を綴る(見出し: &str, 番号: usize, 本番: &許容差依存の細分の記録, 代わり: &許容差依存の細分の記録) {
    接線変位の合計を綴る(見出し, 番号, "本番", 本番);
    接線変位の合計を綴る(見出し, 番号, "代わり", 代わり);
    let (Some(左), Some(右)) = (本番.反復ごと.first(), 代わり.反復ごと.first()) else {
        return;
    };
    println!(
        "  S [{見出し}] 細分{番号}の反復零 本番の比={:.12} 代わりの比={:.12} 差={:+.6e}",
        左.円錐の比(),
        右.円錐の比(),
        右.円錐の比() - 左.円錐の比()
    );
}

