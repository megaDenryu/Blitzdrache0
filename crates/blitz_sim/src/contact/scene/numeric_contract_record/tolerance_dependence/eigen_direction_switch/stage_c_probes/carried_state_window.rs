//! Issue #103の段階Cの第3手の計器(親の2026-09-13の指示)。本番と代わりの捨て方を細分0だけ進め、細分0の終わりに
//! 次の細分へ持ち越される状態を項目ごとに突き合わせる。続けて細分1も進め、その細分で円錐の比の差が出ることを
//! 同じ走行の上で綴る。
//! これが要るのは、段階Cの第1手が「細分0で2つの走行の ‖Σλ_t‖ が単精度の1刻み違う」ことを測った一方、**その違いを
//! 次の細分へ運んでいるのが何かを測っていない**ためである。配置が1ビットも違わないなら運び手は配置ではなく、
//! 錨か履歴か印の側である。配置が違うなら、違った成分が細分の中の段を追う入り口になる。
//! この場面は静穏の仕組みを回していないため、持ち越される静穏の細分の本数は無い。
//! 錨からの接線変位の合計も細分ごとに綴る。静止摩擦は錨からの接線変位を零へ戻す位置拘束であり(判断13)、この変位は
//! 現在の接触点と錨という、ともに0.5メートル規模の2つの量の差である。休止の付近でその差がどの桁まで小さくなるかを
//! 読むと、単精度の表現の刻み(0.5メートルで 5.96e-8 メートル)に対する余裕が分かる。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 細分零の持ち越し -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

