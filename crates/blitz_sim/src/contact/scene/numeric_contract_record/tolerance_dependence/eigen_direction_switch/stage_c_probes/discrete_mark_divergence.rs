// 細分1本で食い違った離散の印の名前。1つも食い違わなければ空である。
fn 食い違った印の名前(
    本番: &許容差依存の細分の記録,
    代わり: &許容差依存の細分の記録,
    本番の場面: &一つの箱と静的な直方体の場面,
    代わりの場面: &一つの箱と静的な直方体の場面,
) -> Vec<&'static str> {
    let mut 名前 = Vec::new();
    if 本番.終わりの接触点ごと.len() != 代わり.終わりの接触点ごと.len() {
        名前.push("接触点の数");
    }
    let 対 = 本番.終わりの接触点ごと.iter().zip(&代わり.終わりの接触点ごと);
    for (左, 右) in 対 {
        if 左.特徴の識別() != 右.特徴の識別() && !名前.contains(&"接触点の特徴の識別") {
            名前.push("接触点の特徴の識別");
        }
        if 左.錨を置き直したか() != 右.錨を置き直したか() && !名前.contains(&"錨を置き直したか") {
            名前.push("錨を置き直したか");
        }
        if 左.滑走中か() != 右.滑走中か() && !名前.contains(&"滑走中か") {
            名前.push("滑走中か");
        }
    }
    if 本番の場面.履歴.項目一覧() != 代わりの場面.履歴.項目一覧() {
        名前.push("接触の履歴の項目(錨と前の細分の接触法線)");
    }
    名前
}

// 細分0の第一反復の入口で、この走行が何本の向きをどの理由で捨てたかと、勝った有効集合を綴る。
fn 捨てた向きの本数を綴る(見出し: &str, 走行: &str, 記録: &許容差依存の細分の記録) {
    let Some(内訳) = 記録.入口.as_ref().and_then(|入口| 入口.一倍の内訳.as_ref()) else {
        println!("  M [{見出し}] 細分0 {走行} 粘着の候補が定まらず内訳が無い");
        return;
    };
    println!(
        "  M [{見出し}] 細分0 {走行} 向き={}本 偽の固有値で捨てた={}本 右辺の判定で捨てた={}本 解いた={}本 有効集合={} 階層の走査が解いた数={} 候補一と勝った有効集合が違うか={:?}",
        内訳.固有の向きごと.len(),
        内訳.捨てた向きの数(擬似逆が固有の向きを捨てた理由::偽の固有値),
        内訳.捨てた向きの数(擬似逆が固有の向きを捨てた理由::右辺が許容差の内側),
        内訳.捨てた向きの数(擬似逆が固有の向きを捨てた理由::捨てていない),
        内訳.有効集合の綴り(),
        記録.解いた回数.階層の走査が解いた数(),
        記録.候補一と勝った有効集合が違うか
    );
}

fn 一つの回しの食い違いを綴る(鉛直軸まわりの回しの度: f32) {
    let 場合 = 細分十六本の場合(鉛直軸まわりの回しの度);
    let 見出し = format!("回し{鉛直軸まわりの回しの度}度");
    println!("[{見出し}] 細分16本の正接{傾きの正接} 離散の印の食い違い");
    let Some(窓の終わり) = 最初に滑走した細分を探す(&場合, 捨て方を当てた適用規則(代表の代わりの捨て方()))
    else {
        println!("  M [{見出し}] 代わりの捨て方がこの姿勢で1本も滑走しなかった。窓が定まらない");
        return;
    };
    let 条件 = 場合.坂の場面の条件を組む();
    let mut 本番の場面 = 場合.場面を当て方で組む(試験の許容差の当て方::本番と同じ当て方());
    let mut 代わりの場面 = 場合.場面を当て方で組む(捨て方を当てた適用規則(代表の代わりの捨て方()));
    for 番号 in 0..=窓の終わり {
        let 入口を読むか = 番号 == 0;
        let 本番の記録 = 本番の場面.記録しながら一細分進める(番号, &条件, 入口を読むか);
        let 代わりの記録 = 代わりの場面.記録しながら一細分進める(番号, &条件, 入口を読むか);
        if 入口を読むか {
            捨てた向きの本数を綴る(&見出し, "本番", &本番の記録);
            捨てた向きの本数を綴る(&見出し, "代わりの捨て方", &代わりの記録);
        }
        let 名前 = 食い違った印の名前(&本番の記録, &代わりの記録, &本番の場面, &代わりの場面);
        if 名前.is_empty() {
            println!("  M [{見出し}] 細分{番号} 4つの離散の印が全部一致");
            continue;
        }
        println!(
            "  M [{見出し}] 細分{番号} 最初に食い違った印={} (窓の終わりは細分{窓の終わり})",
            名前.join("と")
        );
        return;
    }
    println!("  M [{見出し}] 窓(細分0から細分{窓の終わり})のあいだ、4つの離散の印が1度も食い違わなかった");
}

