//! あわせて細分0だけ第一反復の入口を読み、**2つの走行がそれぞれ何本の向きをどの理由で捨てたか**と、勝った有効集合と、
//! 有効集合の走査が解いた連立の回数を綴る。両方とも右辺の判定で零本しか捨てていないなら、「捨てる判断が許容差の
//! 内側に違う残りを置く」という筋書きが細分0では主語を持たないことになる。
