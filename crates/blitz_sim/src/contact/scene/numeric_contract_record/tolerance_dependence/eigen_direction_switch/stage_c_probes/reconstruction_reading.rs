//! Issue #103の段階Cの第4手と第5手の計器が、1本の走行から細分1本について読む量(親の2026-09-13の指示)。
//! 読むのは、速度の再構成の前の量(前の状態から確定した配置までの位置の変化と回る角)と、後の量(再構成した
//! 並進速度と角速度)と、確定した姿勢の4成分である。姿勢の4成分を持つのは、成分ごとの表現の1刻みが角速度で
//! いくつになるかを、その走行の姿勢の上で数えるためである。
//! 再構成は本番と同じ口(`前の状態::確定した配置から速度を再構成する`)を呼び、式を1つも書き写さない。
//! 速度段階を通した後の値はこの型が持たない。そちらは第3手の`carried_state`が持つ。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use crate::contact::scene::slope_geometry::坂の場面の条件;
use crate::contact::scene::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_xpbd::前の状態;

/// 1本の走行の細分1本について読んだ、速度の再構成の前と後の量。
pub(super) struct 一細分の再構成の読み取り {
    pub(super) 位置の変化: Vec<f32>,
    pub(super) 回る角: f32,
    pub(super) 並進速度: Vec<f32>,
    pub(super) 角速度: Vec<f32>,
    pub(super) 確定した姿勢の四成分: [f32; 4],
}

impl 一細分の再構成の読み取り {
    /// 場面を指定の細分だけ進め、再構成の前と後を読む。
    pub(super) fn 一細分を進めて読む(
        場面: &mut 一つの箱と静的な直方体の場面, 条件: &坂の場面の条件, 番号: usize
    ) -> Self {
        let 前 = 前の状態::配置から保存する(&場面.箱の配置);
        let _ = 場面.記録しながら一細分進める(番号, 条件, false);
        let 確定 = 場面.箱の配置;
        let 変化 = 確定.重心の位置() - 前.重心の位置();
        let 回転 = 確定.姿勢().前の姿勢からの微小回転(前.姿勢());
        let 運動状態 = 前.確定した配置から速度を再構成する(&確定, 場面.刻み幅);
        let 速度 = 運動状態.並進速度();
        let 角速度 = 運動状態.角速度();
        Self {
            位置の変化: vec![変化.x().値(), 変化.y().値(), 変化.z().値()],
            回る角: 回転.長さ().値(),
            並進速度: vec![速度.x().値(), 速度.y().値(), 速度.z().値()],
            角速度: vec![角速度.x().値(), 角速度.y().値(), 角速度.z().値()],
            確定した姿勢の四成分: 確定.姿勢().境界用xyzw配列(),
        }
    }
}

/// 2つの並びの成分ごとの差。対で綴る工程が読む。
pub(super) fn 差の並び(左: &[f32], 右: &[f32]) -> Vec<f32> {
    左.iter().zip(右).map(|(左の値, 右の値)| 左の値 - 右の値).collect()
}
