//! 1本の軌道を600刻み進めながら、指定の窓の細分だけ入口を読んで綴る工程(Issue #103の段階Aの一次計測)。
//! 段階Cの`stage_c/failure_probe`から分けているのは、あちらが細分ごとの退避の結末だけを綴る工程であり、
//! こちらが窓の細分について擬似逆の内訳(固有の向きの採否・行ごとの乗数と残差)と円錐の量と倍精度の参照を綴る
//! 工程だからである。合否は判定しない。本番の解法は1ビットも変えない。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::case::許容差依存の診断の場合;
use super::window::細分を綴る窓;
use crate::contact::normal_tangential_system::試験の許容差の当て方;

const 分類を見る刻み数: usize = 600;

/// 1組を600刻み走らせ、窓の細分では入口と円錐の量を、窓の外では最初に滑走した細分と退避の延べ数だけを綴る。
pub(super) fn 一本の軌道を窓つきで綴る(
    場合: &許容差依存の診断の場合, 当て方: 試験の許容差の当て方, 窓: 細分を綴る窓
) {
    let 条件 = 場合.坂の場面の条件を組む();
    let 本数 = 分類を見る刻み数 * 場合.変更.一刻みの細分数();
    let mut 場面 = 場合.場面を当て方で組む(当て方);
    let 初めの重心 = 場面.箱の配置.重心の位置();
    println!("[{}_{}] 細分0〜{} {}", 場合.見出し(), 当て方.綴り(), 本数 - 1, 窓.綴り());
    let mut 最初に滑走した細分 = None;
    let mut 退避の延べ数 = 0;
    for 番号 in 0..本数 {
        let 窓の中か = 窓.含むか(番号);
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, 窓.入口を読むか(番号));
        退避の延べ数 += 記録.解けなかった連立.len();
        if 最初に滑走した細分.is_none() && 記録.滑走中か() {
            最初に滑走した細分 = Some(番号);
            println!("  細分{番号}で最初に滑走中と印された");
        }
        if 窓の中か {
            記録.円錐の量を反復ごとに綴る();
            for (反復, 読み取り) in &記録.解けなかった連立 {
                println!("    F 細分{番号} 反復{反復} {}", 読み取り.綴り());
            }
            if let Some(入口) = &記録.入口 {
                入口.計測点三を綴る();
                入口.計測点一と二を綴る();
                入口.計測点七を綴る();
            }
        }
    }
    println!(
        "  要約 変位={:.3e} 最初に滑走した細分={最初に滑走した細分:?} 退避の延べ数={退避の延べ数} 置き直し{}",
        場面.坂に沿った変位(初めの重心, &条件),
        場面.錨を置き直した細分の延べ数
    );
}
