//! 1本の軌道を600刻み進めながら、指定の窓の細分だけ入口を読んで綴る工程(Issue #103の段階Aと段階A2の一次計測)。
//! 段階Cの`stage_c/failure_probe`から分けているのは、あちらが細分ごとの退避の結末だけを綴る工程であり、
//! こちらが窓の細分について擬似逆の内訳(固有の向きの採否・行ごとの乗数と残差)と円錐の量と倍精度の参照を綴る
//! 工程だからである。走行の全体を1行へ畳む数えは`trajectory_tally`が持つ。合否は判定しない。本番の解法は1ビットも変えない。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::case::許容差依存の診断の場合;
use super::trajectory_tally::一本の軌道の集計;
use super::window::細分を綴る窓;
use crate::contact::normal_tangential_system::試験の許容差の当て方;

const 分類を見る刻み数: usize = 600;
// 保持と滑走を分ける坂に沿った変位の上限(`保持と滑走の分類`と同じ1ミリメートル)。
const 保持の上限メートル: f32 = 1.0e-3;

/// 1組を600刻み走らせ、窓の細分では入口と円錐の量を綴り、走行の全体を1行の数えへ畳む。
pub(super) fn 一本の軌道を窓つきで綴る(
    場合: &許容差依存の診断の場合, 当て方: 試験の許容差の当て方, 窓: 細分を綴る窓
) {
    let 条件 = 場合.坂の場面の条件を組む();
    let 本数 = 分類を見る刻み数 * 場合.変更.一刻みの細分数();
    let mut 場面 = 場合.場面を当て方で組む(当て方);
    let 初めの重心 = 場面.箱の配置.重心の位置();
    println!("[{}_{}] 細分0〜{} {}", 場合.見出し(), 当て方.綴り(), 本数 - 1, 窓.綴り());
    let mut 集計 = 一本の軌道の集計::零から始める();
    for 番号 in 0..本数 {
        let 窓の中か = 窓.含むか(番号);
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, 窓.入口を読むか(番号));
        集計.一細分を数える(&記録, 窓の中か);
        if 窓の中か {
            窓の中の一細分を綴る(番号, &記録);
        }
    }
    let 変位 = 場面.坂に沿った変位(初めの重心, &条件);
    let 滑走中 = 場面.直前の細分の観測.滑走中の接触点の数;
    let 分類 = if 変位.abs() <= 保持の上限メートル && 滑走中 == 0 {
        "保持"
    } else {
        "滑走"
    };
    println!(
        "  要約 [{}_{}] {分類を見る刻み数}刻み {分類} 変位={変位:.3e} {} 置き直し{}",
        場合.見出し(),
        当て方.綴り(),
        集計.綴り(),
        場面.錨を置き直した細分の延べ数
    );
}

// 窓の中の細分1本について、円錐の量・退避の内訳・第一反復の入口の3つを綴る。
fn 窓の中の一細分を綴る(番号: usize, 記録: &super::super::substep_record::許容差依存の細分の記録) {
    記録.円錐の量を反復ごとに綴る();
    for (反復, 読み取り) in &記録.解けなかった連立 {
        println!("    F 細分{番号} 反復{反復} {}", 読み取り.綴り());
    }
    let Some(入口) = &記録.入口 else { return };
    入口.計測点三を綴る();
    入口.計測点一と二を綴る();
    入口.計測点七を綴る();
}
