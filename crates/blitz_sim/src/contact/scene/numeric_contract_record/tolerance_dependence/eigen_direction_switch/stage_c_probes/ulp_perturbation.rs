//! Issue #103の段階Cの第5手の計器が使う、姿勢へ単精度の1刻みだけの摂動を入れる口(親の2026-09-13の指示)。
//! 大きさを指定しないのは、単精度の刻みが値の大きさに比例し、指定した角が姿勢へ入るとは限らないためである。
//! この口は、姿勢の4成分のうち大きさが最も大きい成分を選び、そのビット列を零から遠ざかる向きへ1つ進める。
//! 大きさが最も大きい成分を選ぶのは、その成分の刻みが4成分の中で最も粗く、必ず姿勢を動かせるためである。
//! 四元数の正規化を掛けないのは、正規化の丸めが摂動へ混ざるのを避けるためである。1刻みの変更は単位長からの
//! ずれを 1e-7 の桁しか作らず、姿勢の生成が許す 1e-4 の内側である。
//! 本番の経路はこの口を呼ばない。呼ぶのは対照の走行を組む計器だけである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use crate::contact::scene::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_body::{姿勢, 配置};

/// 1刻みの摂動を入れた結果。入れられなかったときは理由を綴りで持つ。
pub(super) enum 一刻みの摂動の入り方 {
    入った {
        成分の番号: usize,
        入れる前: f32,
        入れた後: f32,
    },
    入らなかった(&'static str),
}

impl 一刻みの摂動の入り方 {
    pub(super) fn 綴り(&self) -> String {
        match self {
            Self::入った {
                成分の番号,
                入れる前,
                入れた後,
            } => format!(
                "姿勢の成分{成分の番号}へ1刻み入った 入れる前={入れる前:.9e}(0x{:08x}) 入れた後={入れた後:.9e}(0x{:08x}) 角にすると約{:.4e}ラジアン",
                入れる前.to_bits(),
                入れた後.to_bits(),
                2.0 * (入れた後 - 入れる前).abs()
            ),
            Self::入らなかった(理由) => format!("1刻みの摂動が入らなかった({理由})"),
        }
    }
}

/// 箱の姿勢の、大きさが最も大きい成分へ1刻みの摂動を入れる。
pub(super) fn 箱の姿勢へ一刻みの摂動を入れる(
    場面: &mut 一つの箱と静的な直方体の場面
) -> 一刻みの摂動の入り方 {
    let mut 四成分 = 場面.箱の配置.姿勢().境界用xyzw配列();
    let Some(成分の番号) = 大きさが最も大きい成分の番号(&四成分) else {
        return 一刻みの摂動の入り方::入らなかった("姿勢の4成分が全部零である");
    };
    let 入れる前 = 四成分[成分の番号];
    let 入れた後 = 零から遠ざかる向きへ一刻み進める(入れる前);
    四成分[成分の番号] = 入れた後;
    match 姿勢::生成する(四成分[0], 四成分[1], 四成分[2], 四成分[3]) {
        Ok(新しい姿勢) => {
            場面.箱の配置 = 配置::二段の位置と姿勢から生成する(場面.箱の配置.重心の位置(), 新しい姿勢);
            一刻みの摂動の入り方::入った {
                成分の番号,
                入れる前,
                入れた後,
            }
        }
        Err(_) => 一刻みの摂動の入り方::入らなかった("1刻み動かした4成分が単位長の検査を通らなかった"),
    }
}

fn 大きさが最も大きい成分の番号(四成分: &[f32; 4]) -> Option<usize> {
    let 番号 = (0..4).max_by(|左, 右| 四成分[*左].abs().total_cmp(&四成分[*右].abs()))?;
    (四成分[番号] != 0.0).then_some(番号)
}

fn 零から遠ざかる向きへ一刻み進める(値: f32) -> f32 {
    let 大きさ = f32::from_bits(値.abs().to_bits() + 1);
    if 値 < 0.0 { -大きさ } else { 大きさ }
}
