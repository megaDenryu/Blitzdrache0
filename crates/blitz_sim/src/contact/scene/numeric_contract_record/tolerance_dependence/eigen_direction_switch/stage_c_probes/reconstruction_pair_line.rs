//! Issue #103の段階Cの第4手の計器が綴る、2本の走行の再構成を並べた行(親の2026-09-13の指示)。
//! `reconstruction_reading`から分けているのは、あちらが1本の走行から量を読む工程であり、こちらが2本を並べて
//! 綴る工程だからである。あわせて、走行に依らない量(姿勢の成分と位置の変化の成分の1刻みが速度でいくつになるか)を
//! 綴る。速度の差をこの量と並べて読めるようにするためである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::reconstruction_floor::{
    位置の変化の一刻みが速度へ写る量, 姿勢の一刻みが角速度へ写る量, 成分ごとの量を綴る
};
use super::reconstruction_reading::{一細分の再構成の読み取り, 差の並び};

impl 一細分の再構成の読み取り {
    /// 相手の走行の読み取りと並べて、再構成の前と後と、表現の1刻みが速度へ写る量を綴る。
    pub(super) fn 相手と並べて綴る(&self, 見出し: &str, 刻み幅の秒: f32, 相手: &Self) {
        println!(
            "  R [{見出し}] 再構成の前 位置の変化の差: {}",
            成分ごとの量を綴る(&差の並び(&self.位置の変化, &相手.位置の変化))
        );
        println!(
            "  R [{見出し}] 再構成の前 回る角: 本番={:.6e} 代わり={:.6e} 差={:+.6e}",
            self.回る角,
            相手.回る角,
            self.回る角 - 相手.回る角
        );
        println!(
            "  R [{見出し}] 再構成の後 並進速度の差: {}",
            成分ごとの量を綴る(&差の並び(&self.並進速度, &相手.並進速度))
        );
        println!(
            "  R [{見出し}] 再構成の後 角速度: 本番={} 代わり={}",
            成分ごとの量を綴る(&self.角速度),
            成分ごとの量を綴る(&相手.角速度)
        );
        println!(
            "  R [{見出し}] 再構成の後 角速度の差: {}",
            成分ごとの量を綴る(&差の並び(&self.角速度, &相手.角速度))
        );
        self.表現の一刻みが速度へ写る量を綴る(見出し, 刻み幅の秒);
    }

    /// 姿勢の成分ごとと位置の変化の成分ごとに、1刻みが速度でいくつになるかを綴る。
    pub(super) fn 表現の一刻みが速度へ写る量を綴る(&self, 見出し: &str, 刻み幅の秒: f32) {
        println!(
            "  R [{見出し}] 姿勢の成分の1刻みが角速度へ写る量: {}",
            成分ごとの量を綴る(&self.姿勢の量子の並び(刻み幅の秒))
        );
        println!(
            "  R [{見出し}] 位置の変化の成分の1刻みが並進速度へ写る量: {}",
            成分ごとの量を綴る(&self.位置の量子の並び(刻み幅の秒))
        );
    }

    /// 姿勢の4成分それぞれの1刻みが角速度へ写る量。
    pub(super) fn 姿勢の量子の並び(&self, 刻み幅の秒: f32) -> Vec<f32> {
        self.確定した姿勢の四成分
            .iter()
            .map(|成分| 姿勢の一刻みが角速度へ写る量(*成分, 刻み幅の秒))
            .collect()
    }

    /// 位置の変化の3成分それぞれの1刻みが並進速度へ写る量。
    pub(super) fn 位置の量子の並び(&self, 刻み幅の秒: f32) -> Vec<f32> {
        self.位置の変化
            .iter()
            .map(|成分| 位置の変化の一刻みが速度へ写る量(*成分, 刻み幅の秒))
            .collect()
    }
}
