//! 一次計測が細分ごとの量を綴る範囲と、その範囲で第一反復の入口まで読むかの指定(Issue #103の段階A)。
//! 4800細分の全部で入口を読むと、1細分につき倍精度の求解が3回走るため計測が現実的な時間で終わらない。
//! 分類が分岐する細分の手前から後ろまでの範囲だけを綴る。範囲を数の組で呼び出し側へ持たせず1つの型にするのは、
//! 始まりと終わりを取り違えても数どうしでは型が止めないためである。入口を読まない枝を持つのは、入口の読み取りが
//! 1倍と2倍を比べる形に固定されており、0.5倍の軌道では比べる相手が場面の倍率と合わないためである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

/// 細分ごとの量を綴る範囲(両端を含む)と、その範囲での読み方。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 細分を綴る窓 {
    /// 円錐の量と退避の内訳だけを綴り、擬似逆の内訳と倍精度の参照は読まない。
    円錐と退避だけを綴る { 始まりの細分: usize, 終わりの細分: usize },
    /// 円錐の量と退避の内訳に加えて、第一反復の入口(擬似逆の内訳と倍精度の参照)も読む。
    入口も読む { 始まりの細分: usize, 終わりの細分: usize },
}

impl 細分を綴る窓 {
    /// この細分を綴るか。
    pub(super) fn 含むか(&self, 細分の番号: usize) -> bool {
        let (始まり, 終わり) = self.始まりと終わり();
        細分の番号 >= 始まり && 細分の番号 <= 終わり
    }

    /// この細分で第一反復の入口まで読むか。
    pub(super) fn 入口を読むか(&self, 細分の番号: usize) -> bool {
        matches!(self, Self::入口も読む { .. }) && self.含むか(細分の番号)
    }

    /// 表の見出しへ綴る形。
    pub(super) fn 綴り(&self) -> String {
        let (始まり, 終わり) = self.始まりと終わり();
        let 読み方 = match self {
            Self::円錐と退避だけを綴る { .. } => "円錐と退避だけ",
            Self::入口も読む { .. } => "入口も読む",
        };
        format!("窓={始まり}〜{終わり}({読み方})")
    }

    fn 始まりと終わり(&self) -> (usize, usize) {
        match self {
            Self::円錐と退避だけを綴る {
                始まりの細分, 終わりの細分
            }
            | Self::入口も読む {
                始まりの細分, 終わりの細分
            } => (*始まりの細分, *終わりの細分),
        }
    }
}
