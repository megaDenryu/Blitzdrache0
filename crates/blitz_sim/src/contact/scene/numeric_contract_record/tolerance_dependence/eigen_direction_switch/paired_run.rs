//! Issue #103の段階Cの第1手の計器が対にする2本の走行(親の2026-09-13の指示)。同じ窓を2本同時に進め、細分ごとの
//! 円錐の比と、2本の差と、1つ手前の細分の差の何倍かと、法線の乗数の合計と接線の合力の大きさを1行へ綴る。
//! 差は「2本目の比 − 1本目の比」と定める。段階Bの表92は「代わりの捨て方の比 − 本番の比」で綴っており、本命の対で
//! 1本目を本番、2本目を代わりの捨て方に置けば同じ向きの量になる。
//! 比はどちらも反復零の後の読み取りである(段階Bの表92と同じ読み取りである)。円錐の判定が滑走の瞬間に読んだ比は
//! 反復零の読み取りでは読めないため、超えた集合の読み取りを同じ細分の別の行として添える。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::substep_record::許容差依存の細分の記録;
use crate::contact::scene::slope_geometry::坂の場面の条件;
use crate::contact::scene::substep_harness::一つの箱と静的な直方体の場面;

/// 同じ窓を同時に進める2本の走行。
pub(super) struct 対にした二つの走行 {
    見出し: &'static str,
    一本目: 一つの箱と静的な直方体の場面,
    二本目: 一つの箱と静的な直方体の場面,
    手前の細分の差: Option<f64>,
}

impl 対にした二つの走行 {
    pub(super) fn 見出しと二本から組む(
        見出し: &'static str,
        一本目: 一つの箱と静的な直方体の場面,
        二本目: 一つの箱と静的な直方体の場面,
    ) -> Self {
        Self {
            見出し,
            一本目,
            二本目,
            手前の細分の差: None,
        }
    }

    /// 細分0から窓の終わりまで2本を同時に進め、細分ごとに対の行を綴る。
    pub(super) fn 窓を細分ごとに綴る(&mut self, 条件: &坂の場面の条件, 窓の終わり: usize) {
        for 番号 in 0..=窓の終わり {
            let 一本目の記録 = self.一本目.記録しながら一細分進める(番号, 条件, false);
            let 二本目の記録 = self.二本目.記録しながら一細分進める(番号, 条件, false);
            self.一細分の対を綴る(番号, &一本目の記録, &二本目の記録);
        }
    }

    fn 一細分の対を綴る(
        &mut self, 番号: usize, 一本目: &許容差依存の細分の記録, 二本目: &許容差依存の細分の記録
    ) {
        let 見出し = self.見出し;
        let (Some(一), Some(二)) = (一本目.反復ごと.first(), 二本目.反復ごと.first()) else {
            println!("  P 細分{番号} [{見出し}] 反復の読み取りが無い");
            return;
        };
        let 差 = 二.円錐の比() - 一.円錐の比();
        let 何倍か = self.手前の差の何倍かを綴って覚える(差);
        println!(
            "  P 細分{番号} [{見出し}] 一本目の比={:.6} 二本目の比={:.6} 差={差:+.6e} 手前の差の何倍か={何倍か} 一本目Σλ_n={:.6e} 一本目‖Σλ_t‖={:.6e} 二本目Σλ_n={:.6e} 二本目‖Σλ_t‖={:.6e}",
            一.円錐の比(),
            二.円錐の比(),
            一.法線の乗数の合計,
            一.接線の合力の大きさ,
            二.法線の乗数の合計,
            二.接線の合力の大きさ
        );
        超えた集合を綴る(番号, 見出し, "一本目", 一本目);
        超えた集合を綴る(番号, 見出し, "二本目", 二本目);
    }

    // 1つ手前の細分の差に対する大きさの比を綴り、この細分の差を覚える。手前が無いか零なら「—」である。
    fn 手前の差の何倍かを綴って覚える(&mut self, 差: f64) -> String {
        let 綴り = match self.手前の細分の差 {
            Some(手前) if 手前 != 0.0 => format!("{:.3}", 差.abs() / 手前.abs()),
            _ => "—".to_owned(),
        };
        self.手前の細分の差 = Some(差);
        綴り
    }
}

// 円錐を超えて滑走へ移った集合の読み取りを、同じ細分の別の行として綴る。
fn 超えた集合を綴る(番号: usize, 見出し: &str, 走行: &str, 記録: &許容差依存の細分の記録) {
    for (反復, 読み取り) in &記録.円錐を超えた集合 {
        println!("  B 細分{番号} [{見出し}] {走行} 反復{反復} {}", 読み取り.綴り());
    }
}
