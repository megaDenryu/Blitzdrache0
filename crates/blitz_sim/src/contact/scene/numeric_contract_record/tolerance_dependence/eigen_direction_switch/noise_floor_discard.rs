use super::{窓の始まりの細分, 窓の終わりの細分, 遠方の正接零点五八の場合};
use crate::contact::normal_tangential_system::{
    擬似逆が右辺の向きを捨てる判定の当て方, 解けたと見なす許容差の倍率, 試験の許容差の当て方
};

// 段階A2の追補の表42が測った、保持している箱の接線変位の雑音の床(メートル)。
const 接線の雑音の床メートル: f32 = 6.65e-8;
// 雑音の床へ掛ける安全率。段階A3の計測Bが測り直した床の最大に対する余裕である。
const 雑音の床へ掛ける安全率: f32 = 4.0;
const 振る受理の倍率: [f32; 3] = [0.5, 1.0, 2.0];

pub(super) fn 候補シータの適用規則() -> 試験の許容差の当て方 {
    試験の許容差の当て方::本番と同じ当て方().右辺の向きを捨てる判定を差し替える(
        擬似逆が右辺の向きを捨てる判定の当て方::接線の雑音の床へ安全率を掛けた長さで捨てる {
            長さメートル: 接線の雑音の床メートル * 雑音の床へ掛ける安全率,
        },
    )
}

fn 窓() -> 細分を綴る窓 {
    細分を綴る窓::入口も読む {
        始まりの細分: 窓の始まりの細分(),
        終わりの細分: 窓の終わりの細分(),
    }
}

// 1つの適用規則を、受理の倍率3つの軌道で走らせる。
fn 一つの適用規則を倍率ごとに綴る(適用規則: 試験の許容差の当て方) {
    for 比 in 振る受理の倍率 {
        let 振った = 適用規則.受理の倍率を差し替える(解けたと見なす許容差の倍率::比から生成する(比));
        一本の軌道を窓つきで綴る(&遠方の正接零点五八の場合(), 振った, 窓());
    }
}

