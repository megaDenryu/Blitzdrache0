//! Issue #103の段階A3の計測A。擬似逆の右辺の判定 |β_k| ≤ δ_k が比べる δ_i だけを、座標の刻みからでなく接線の雑音の床へ
//! 安全率を掛けた1つの長さから導く枝(候補(θ))を、遠方(移動20.4999)・正接0.58・受理の倍率0.5・1・2倍で600刻み走らせ、
//! 本番の形と対で綴る計器(親の2026-09-12の指示)。
//! 候補(θ)の δ_i は擬似逆の採否だけへ届き、行を積む閾値と受理の判定(A・B1・B4)へは届かない。候補(ζ)が保持を壊した
//! 原因は δ_i を下げた先が行を積む閾値へも届き、雑音の行を連立方程式へ積んだことであった(段階A2の追補の観測4)。
//! 候補(θ)はその経路を閉じたまま、右辺の判定だけを座標から切り離す枝である。
//! 綴るのは、分類・坂に沿った変位・最初に滑走した細分・退避の件数と理由・窓(細分3320〜3345)の円錐の比の振れ幅・
//! 採否が変わった向きの件数・乗数の増分の最大と、窓で右辺の判定が捨てた向きの2つの群(真の向きと階数側)の延べ数である。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 候補(θ)の適用規則を組む口は、退行を測る計器(`noise_floor_regression`)も読む。
//! 実行は `cargo test -p blitz_sim --release 雑音の床で捨てる -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

