/// 1つの場面を細分ごとに進め、細分の終わりの |C_t| の最大と、その細分の接線の行の δ_t を綴る。
/// 箱の腕の長さを振る計器(`noise_floor_by_box_arm`)が同じ綴りで読むため、この木の中へ開いている。
pub(super) fn 一つの場面の雑音の床を綴る(場合: &許容差依存の診断の場合) {
    let 条件 = 場合.坂の場面の条件を組む();
    let mut 場面 = 場合.場面を当て方で組む(試験の許容差の当て方::本番と同じ当て方());
    let 初めの重心 = 場面.箱の配置.重心の位置();
    println!("[{}] 細分0〜{} の接線の雑音の床", 場合.見出し(), 綴る細分の本数 - 1);
    let mut 全体の最大 = 0.0f64;
    for 番号 in 0..綴る細分の本数 {
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, false);
        let 最大 = 記録.終わりの接線変位.iter().fold(0.0f64, |合計, 値| 合計.max(値.abs()));
        全体の最大 = 全体の最大.max(最大);
        println!(
            "  J 細分{番号} |C_t|の最大={最大:.4e} δ_t={:.4e} 点の数={} 滑走中={}",
            記録.接線の行の許容差,
            記録.終わりの接線変位.len(),
            記録.滑走中か()
        );
    }
    println!(
        "  要約 [{}] |C_t|の最大={全体の最大:.4e} 坂に沿った変位={:.3e}",
        場合.見出し(),
        場面.坂に沿った変位(初めの重心, &条件)
    );
}

