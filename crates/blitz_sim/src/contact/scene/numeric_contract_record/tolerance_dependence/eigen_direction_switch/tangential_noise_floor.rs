//! Issue #103の段階A2の追補。十分に緩い坂(正接0.30)で保持している箱の、錨からの接線変位 C_t が細分ごとに
//! どの桁に居るかを綴る計器(親の2026-09-12の指示)。C_t は接線の行の右辺そのものであり、保持している箱では
//! 物理の滑りでなく表現の刻みと演算の丸めが作る雑音である。この雑音の床が δ_i と同じ桁なら、δ_i は
//! 「この行は数値上解けている」と見なす閾値として実測に裏づけられる。桁が2つ以上離れていれば裏づけられない。
//! 原点付近と遠方(坂の面の法線の向きへ20.4999メートル)の2つを同じ形で綴るのは、δ_i が座標の粗い位置の刻みから
//! 決まり、遠方で43倍になるためである。候補(ζ)は δ_i をその43倍のぶんだけ下げる枝であり、下げた先が雑音の床を
//! 下回るなら、雑音の行を連立へ積むことになる。
//! 合否は判定しない。実行は `cargo test -p blitz_sim --release 接線の雑音の床 -- --ignored --nocapture` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

