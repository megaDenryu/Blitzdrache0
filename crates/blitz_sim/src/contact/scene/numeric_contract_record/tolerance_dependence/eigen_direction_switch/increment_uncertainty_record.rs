// 細分1本の2つの正規化の分母と、増分がいちばん大きい向きの量を綴る(計測6)。
fn 一細分の二つの分母を綴る(番号: usize, 内訳: &単精度の解の内訳, 反復零の法線の乗数の合計: f64) {
    let 硬い向きの増分 = 内訳.右辺をいちばん硬い向きで解いたときの増分();
    let (最大の増分, 率) = 内訳
        .固有の向きごと
        .iter()
        .filter(|向き| 向き.固有値 > 0.0)
        .map(|向き| ((向き.右辺の射影 / 向き.固有値).abs(), 内訳.偽の固有値の下限 / 向き.固有値))
        .max_by(|左, 右| 左.0.total_cmp(&右.0))
        .unwrap_or((0.0, 0.0));
    let 法線の合計で割る = if 反復零の法線の乗数の合計 > 0.0 {
        f64::from(最大の増分) / 反復零の法線の乗数の合計
    } else {
        f64::INFINITY
    };
    println!(
        "  S 細分{番号} Σλ_n={反復零の法線の乗数の合計:.4e} ‖b‖={:.4e} ‖b‖/λ_max={硬い向きの増分:.4e} 最大の増分={最大の増分:.4e} 最大の増分/Σλ_n={法線の合計で割る:.4e} 最大の増分/(‖b‖/λ_max)={:.4e} その向きの不確かさの率={率:.4e}",
        内訳.右辺の大きさ,
        if 硬い向きの増分 > 0.0 {
            最大の増分 / 硬い向きの増分
        } else {
            0.0
        }
    );
}

fn 一つの場面の増分と率を綴る(場合: &許容差依存の診断の場合) {
    let 条件 = 場合.坂の場面の条件を組む();
    let mut 場面 = 場合.場面を当て方で組む(試験の許容差の当て方::本番と同じ当て方());
    let mut 広がり = 増分と不確かさの率の広がり::零から始める();
    println!("[{}] 細分0〜{} 増分と不確かさの率", 場合.見出し(), 綴る細分の本数 - 1);
    for 番号 in 0..綴る細分の本数 {
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, true);
        let Some(内訳) = 記録.入口.as_ref().and_then(|入口| 入口.一倍の内訳.as_ref()) else {
            println!("  S 細分{番号} 粘着の候補が定まらず");
            continue;
        };
        広がり.一回の求解を数える(内訳);
        一細分の二つの分母を綴る(番号, 内訳, 記録.反復ごと.first().map_or(0.0, |反復| 反復.法線の乗数の合計));
    }
    println!("  要約 [{}] {}", 場合.見出し(), 広がり.綴り());
}

