// 1細分の求解の中身を、向きごと・行ごと・反復ごと・接触点ごとの4段で綴る。
fn 一細分を綴る(見出し: &str, 記録: &許容差依存の細分の記録) {
    let 番号 = 記録.番号;
    let 接触点の数 = 記録.終わりの接触点ごと.len();
    match 記録.入口.as_ref().and_then(|入口| 入口.一倍の内訳.as_ref()) {
        Some(内訳) => {
            println!(
                "  X 細分{番号} [{見出し}] 接触点={接触点の数}個 有効集合={} 行数={} λ_max={:.4e} 偽の固有値の下限={:.4e} ‖b‖={:.4e}",
                内訳.有効集合の綴り(),
                内訳.行ごとの残差.len(),
                内訳.最大の固有値,
                内訳.偽の固有値の下限,
                内訳.右辺の大きさ
            );
            向きごとを綴る(番号, 見出し, 内訳, 枝の最大の固有値への相対比);
            行ごとを綴る(番号, 見出し, 内訳);
        }
        None => println!("  X 細分{番号} [{見出し}] 接触点={接触点の数}個 粘着の候補が定まらず内訳が無い"),
    }
    反復ごとを綴る(見出し, 記録);
    接触点ごとを綴る(見出し, 記録);
}

// 本番と枝で綴りが違う量のうち、まだ記していないものをこの細分の番号で記す。
fn 差が最初に出た細分を記す(
    一覧: &mut Vec<(&'static str, usize)>,
    番号: usize,
    本番: &許容差依存の細分の記録,
    枝: &許容差依存の細分の記録,
) {
    let 本番の量 = 細分一本から読んだ名前つきの量の並び::細分の記録から読む(本番);
    let 枝の量 = 細分一本から読んだ名前つきの量の並び::細分の記録から読む(枝);
    for 名前 in 本番の量.相手と違う量の名前(&枝の量) {
        if !一覧.iter().any(|(記した名前, _)| *記した名前 == 名前) {
            一覧.push((名前, 番号));
        }
    }
}

fn 一つの回しの窓を対で綴る(鉛直軸まわりの回しの度: f32) {
    let 場合 = 細分十六本の場合(鉛直軸まわりの回しの度);
    println!("[回し{鉛直軸まわりの回しの度}度] 細分16本の正接{傾きの正接} の本番と枝の分岐の窓");
    let Some(滑走した細分) = 最初に滑走した細分を探す(&場合, 捨て方を当てた適用規則(枝の捨て方())) else {
        println!("  D 枝がこの姿勢で1本も滑走しなかった。窓が定まらない");
        return;
    };
    println!("  D 枝が最初に滑走した細分={滑走した細分}。窓は細分0から細分{滑走した細分}である");
    let 条件 = 場合.坂の場面の条件を組む();
    let mut 本番の場面 = 場合.場面を当て方で組む(試験の許容差の当て方::本番と同じ当て方());
    let mut 枝の場面 = 場合.場面を当て方で組む(捨て方を当てた適用規則(枝の捨て方()));
    let mut 差が最初に出た細分 = Vec::new();
    for 番号 in 0..=滑走した細分 {
        let 本番の記録 = 本番の場面.記録しながら一細分進める(番号, &条件, true);
        let 枝の記録 = 枝の場面.記録しながら一細分進める(番号, &条件, true);
        一細分を綴る(本番の見出し, &本番の記録);
        一細分を綴る(枝の見出し, &枝の記録);
        差が最初に出た細分を記す(&mut 差が最初に出た細分, 番号, &本番の記録, &枝の記録);
    }
    for (名前, 番号) in &差が最初に出た細分 {
        println!("  D 回し{鉛直軸まわりの回しの度}度 本番と枝で最初に違った量={名前} 細分{番号}");
    }
}

