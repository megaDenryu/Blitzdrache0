#![cfg(test)]

use super::trajectory::一本の軌道を窓つきで綴る;
use super::window::細分を綴る窓;
use super::{窓の始まりの細分, 窓の終わりの細分, 遠方の正接零点五八の場合};
use crate::contact::normal_tangential_system::{
    擬似逆が右辺の向きを捨てる判定の当て方, 解けたと見なす許容差の倍率, 試験の許容差の当て方
};

const 振る受理の倍率: &[f32] = &[0.5, 1.0, 2.0];

pub(super) fn 候補シータダッシュの適用規則() -> 試験の許容差の当て方 {
    試験の許容差の当て方::本番と同じ当て方()
        .右辺の向きを捨てる判定を差し替える(擬似逆が右辺の向きを捨てる判定の当て方::基準原点に相対な座標から導く許容差で捨てる)
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 基準原点で捨てる_候補シータダッシュを受理の倍率ごとに綴る() {
    for &比 in 振る受理の倍率 {
        let 適用規則 = 候補シータダッシュの適用規則().受理の倍率を差し替える(解けたと見なす許容差の倍率::比から生成する(比));
        let 窓 = 細分を綴る窓::入口も読む {
            始まりの細分: 窓の始まりの細分(),
            終わりの細分: 窓の終わりの細分(),
        };
        一本の軌道を窓つきで綴る(&遠方の正接零点五八の場合(), 適用規則, 窓);
    }
}
