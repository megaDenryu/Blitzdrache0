//! そのうち擬似逆の採否だけへ当て、行を積む閾値と受理の判定(A・B1・B4)は座標から導く本番の δ_i のままにする枝である。
//! 候補(θ)が1つの長さを全部の場面へ据えて剛体どうしの接触で退行したのに対し、この枝は行ごとに腕の大きさで決まる。
