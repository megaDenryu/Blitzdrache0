//! Issue #103の段階Cの第7手の計器(親の2026-09-13の指示)。代わりの捨て方を**先頭の何細分かだけ**適用し、それ以降は
//! 本番と同じ判定へ戻す変種を、素の本番と対にして9600細分進める。当てる細分の本数は1本と4本の2つで測る。
//! 4本を測るのは、代わりの捨て方が回し0度と回し30度で滑走へ移る細分が4であり、**その細分の求解に代わりの捨て方が
//! 当たっていること自体**が要るのかを分けるためである。4本当てて細分4以降を本番へ戻した走行が超えないなら、
//! 細分3までに溜まった状態そのものは超過を起こさない。
//! これが要るのは、第5手が「代わりの捨て方が細分0で入れる回転の6433倍の摂動を1回入れた本番は9600細分のあいだ
//! 1度も円錐を超えない」ことを測った一方、代わりの捨て方は4細分から12細分で超えるためである。量では説明が付かない。
//! 残る候補は2つであり、1つは**くり返し**(代わりの捨て方は毎細分それを解き続ける)、もう1つは**向き**である。
//! この計器はくり返しを切る。細分0でだけ適用した変種が超えないなら、くり返しが名指しされる。超えるなら外れる。
//! 判定の切り替えは、場面が持つ試験の許容差の当て方を細分0の後で本番のものへ差し替えることで行う。新しい閾値も
//! 定数も作らない。本番の判定と閾値と既定は1つも変えていない。合否は判定しない。
//! 実行は `cargo test -p blitz_sim --release 細分零だけの捨て方 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

