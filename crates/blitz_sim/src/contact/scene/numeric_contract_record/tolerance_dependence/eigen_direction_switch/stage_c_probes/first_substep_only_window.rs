fn 反復零の後の円錐の比(記録: &許容差依存の細分の記録) -> f64 {
    記録.反復ごと.first().map_or(0.0, |反復| 反復.円錐の比())
}

fn 超過を数える(溜まり: &mut 長い走行の溜まり, 番号: usize, 走行: &str, 記録: &許容差依存の細分の記録) {
    for (反復, 読み取り) in &記録.円錐を超えた集合 {
        溜まり.一細分の超過を数える(番号, 走行, &format!("反復{反復} {}", 読み取り.綴り()));
    }
}

fn 一つの回しの先頭だけの捨て方を綴る(鉛直軸まわりの回しの度: f32, 当てる細分の本数: usize) {
    let 場合 = 細分十六本の場合(鉛直軸まわりの回しの度);
    let 条件 = 場合.坂の場面の条件を組む();
    let 見出し = format!("回し{鉛直軸まわりの回しの度}度");
    let 本数 = 走らせる刻みの数 * 場合.変更.一刻みの細分数();
    let 本番 = 試験の許容差の当て方::本番と同じ当て方();
    let mut 素の場面 = 場合.場面を当て方で組む(本番);
    let mut 変種の場面 = 場合.場面を当て方で組む(捨て方を当てた適用規則(代表の代わりの捨て方()));
    println!("[{見出し}] 細分16本の正接{傾きの正接} 代わりの捨て方を先頭の{当てる細分の本数}細分だけ適用し、{本数}細分進める");
    let mut 溜まり = 長い走行の溜まり::見出しから始める(format!("{見出し}_先頭{当てる細分の本数}細分"));
    for 番号 in 0..本数 {
        let 素の記録 = 素の場面.記録しながら一細分進める(番号, &条件, false);
        let 変種の記録 = 変種の場面.記録しながら一細分進める(番号, &条件, false);
        if 番号 + 1 == 当てる細分の本数 {
            変種の場面.試験の許容差の当て方 = 本番;
        }
        溜まり.一細分の差を数える(番号, 反復零の後の円錐の比(&素の記録), 反復零の後の円錐の比(&変種の記録));
        超過を数える(&mut 溜まり, 番号, "素の本番", &素の記録);
        超過を数える(&mut 溜まり, 番号, "先頭だけ代わりの捨て方", &変種の記録);
    }
    溜まり.要約を綴る(本数);
}

