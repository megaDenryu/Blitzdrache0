// 細分1本の2段を綴り、この細分の特徴の識別の並びを返す。
fn 一細分を二段で綴る(記録: &許容差依存の細分の記録, 有効集合の綴り: &str) -> Vec<接触の特徴の識別> {
    let 番号 = 記録.番号;
    println!(
        "  R 細分{番号} 点の数={} 有効集合={有効集合の綴り} 置き直した点={} 滑走中の点={}",
        記録.終わりの接触点ごと.len(),
        記録.置き直した点の数(),
        記録.滑走中の点の数()
    );
    for (点の番号, 点) in 記録.終わりの接触点ごと.iter().enumerate() {
        println!("    R 細分{番号} 点{点の番号} {}", 点.綴り());
    }
    記録.終わりの接触点ごと.iter().map(|点| 点.特徴の識別()).collect()
}

// 1つの場面を細分ごとに進め、2段の綴りと、識別の並びが前の細分から変わった件数を数える。
fn 一つの場面の接触の識別を綴る(場合: &許容差依存の診断の場合) {
    let 条件 = 場合.坂の場面の条件を組む();
    let mut 場面 = 場合.場面を当て方で組む(試験の許容差の当て方::本番と同じ当て方());
    let 初めの重心 = 場面.箱の配置.重心の位置();
    let (mut 直前の置き直しの延べ数, mut 開始の延べ数, mut 置き直した細分の数) = (0, 0, 0);
    let (mut 直前の識別, mut 識別が変わった細分の数) = (Vec::new(), 0);
    println!("[{}] 細分0〜{} の接触の識別と錨の置き直し", 場合.見出し(), 綴る細分の本数 - 1);
    for 番号 in 0..綴る細分の本数 {
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, true);
        let 有効集合 = 記録
            .入口
            .as_ref()
            .and_then(|入口| 入口.一倍の内訳.as_ref())
            .map_or_else(|| "定まらず".to_owned(), |内訳| 内訳.有効集合の綴り());
        let 識別 = 一細分を二段で綴る(&記録, &有効集合);
        開始の延べ数 += 場面.直前の細分の観測.開始した接触点の数;
        置き直した細分の数 += usize::from(場面.錨を置き直した細分の延べ数 > 直前の置き直しの延べ数);
        直前の置き直しの延べ数 = 場面.錨を置き直した細分の延べ数;
        識別が変わった細分の数 += usize::from(番号 > 0 && 識別 != 直前の識別);
        直前の識別 = 識別;
    }
    println!(
        "  要約 [{}] 開始の延べ数={開始の延べ数} 錨を置き直した細分={置き直した細分の数}本 識別の並びが前の細分と違う細分={識別が変わった細分の数}本 / {綴る細分の本数}本 坂に沿った変位={:.3e}",
        場合.見出し(),
        場面.坂に沿った変位(初めの重心, &条件)
    );
}

fn 一つの回しを綴る(鉛直軸まわりの回しの度: f32) {
    一つの場面の接触の識別を綴る(&回しを付けた緩い坂の場合(
        段階A1の場面からの一つの変更::無し,
        鉛直軸まわりの回しの度,
    ));
}

