//! Issue #103の段階A5の計測2。緩い坂(正接0.30)で保持している箱の、錨を置き直した細分と、接触点の特徴の識別が
//! 細分をまたいで変わった件数を、姿勢ごとに綴る計器(親の2026-09-12の指示)。
//! これが要るのは、段階A3の表46が測った回し45度の接線の雑音の床(7.9719e-7メートル。他の3つの坂の10.9倍)が、
//! 丸めから来るのか離散の事象から来るのかを、誰もまだ分けていないためである。段階A5の計測3は、この床が箱の腕の
//! 長さに比例しないことを測った(丸めではない)。残る候補は、接触点の識別が細分をまたいで入れ替わることである。
//! 判断16の併走は、前の細分と同じ特徴の識別を持つ接触だけを継続とし、無ければ開始として錨をその細分の接触点へ置く。
//! 綴るのは細分ごとに2段である。1段目は接触点の数・開始した接触点の数・錨を置き直したか・有効集合であり、
//! 2段目は接触点1つずつの特徴の識別・接線変位・接線と法線の乗数・その点の錨を置き直したかである。
//! 45度の定常が2つの値を1細分おきに交互に取るとき、入れ替わっているのが識別なのか乗数の配分なのかを、
//! 2段目が直に分ける。入れ替わるのが識別なら原因の層は接触の候補と履歴であり、乗数の配分だけなら層は解法である。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 姿勢ごとの接触の識別 -- --ignored --nocapture --test-threads=1` である。
