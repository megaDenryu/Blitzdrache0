//! 細分の第一反復の入口で、接触点1つずつの接線の行が連立方程式へ入ったかどうかを読む工程(Issue #103の段階A5の計測2の追加)。
//! 判断13の2026-09-12の改訂(候補(i')の本実装)は、錨からの接線変位 C_t がその行の解けたと見なす許容差 δ_t の内側の行を
//! 積まない。積まない行はその細分で零へ戻されないため、箱は許容差の内側を自由に流れる。したがって、姿勢によって
//! 止まる位置が10倍違う現象がこの規則の帰結かどうかは、点ごとに「積んだか」「δ_t はいくつか」「|C_t| ÷ δ_t はいくつか」
//! 「積んだなら元の行空間の残差はいくつか」の4つを並べて初めて読める。
//! 細分の終わりを読む`contact_point_ending`から分けているのは、あちらが補正を終えた後の状態を読む工程であり、
//! こちらが補正を1度も当てていない入口で、連立方程式の組み立てそのものを読む工程だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::normal_tangential_system::単精度の解の内訳;
use crate::contact::scene::substep_harness::一つの箱と静的な直方体の場面;
use crate::contact::static_friction::静止摩擦の連立へ点を入れた結果;
use crate::rigid_body::配置;
use crate::rigid_xpbd::姿勢自由度の参加者;

/// 接触点1つの接線の行が、第一反復の入口で連立方程式へどう入ったか。
pub(super) struct 接線の行の入り方の読み取り {
    点の番号: usize,
    点を入れた結果: 静止摩擦の連立へ点を入れた結果,
    残差と許容差の綴り: String,
    元の行空間の残差: Option<f32>,
}

impl 接線の行の入り方の読み取り {
    /// 表へ綴る形。
    pub(super) fn 綴り(&self) -> String {
        let 残差 = match self.元の行空間の残差 {
            Some(値) => format!("{値:.4e}"),
            None => "積まず".to_owned(),
        };
        format!(
            "点{} 入れた結果={:?} C_t/δ_t={} 元の行空間の残差={残差}",
            self.点の番号, self.点を入れた結果, self.残差と許容差の綴り
        )
    }
}

impl 一つの箱と静的な直方体の場面 {
    /// 第一反復の入口で、点ごとの接線の行の入り方を読む。状態は書き換えない。
    /// 元の行空間の残差を埋めるのは、有効集合が全部の点を含む求解だけである。含まない求解では行と点の対応が
    /// 番号の順で決まらないため、埋めずに無しにする。
    pub(super) fn 接線の行の入り方を読む(
        &self,
        接触点集合: &[剛体と静的世界の接触拘束],
        配置: &配置,
        内訳: Option<&単精度の解の内訳>,
    ) -> Vec<接線の行の入り方の読み取り> {
        let 参加者 = 姿勢自由度の参加者::動的(*配置, &self.箱の質量特性);
        let (連立, 点を入れた結果) = self.法線と接線の連立を許容差の当て方で組む(接触点集合, &参加者, self.試験の許容差の当て方);
        let 全部の点が有効な内訳 = 内訳.filter(|読み| 読み.法線の行の数 == 連立.点の数());
        let mut 積んだ行の数 = 0;
        (0..連立.点の数())
            .map(|番号| {
                let 積んだか = 点を入れた結果[番号] == 静止摩擦の連立へ点を入れた結果::一行を積んだ;
                let 元の行空間の残差 = 積んだか
                    .then(|| 全部の点が有効な内訳.and_then(|読み| 読み.行ごとの残差.get(読み.法線の行の数 + 積んだ行の数).copied()))
                    .flatten();
                積んだ行の数 += usize::from(積んだか);
                接線の行の入り方の読み取り {
                    点の番号: 番号,
                    点を入れた結果: 点を入れた結果[番号],
                    残差と許容差の綴り: 連立
                        .点の接線の残差と許容差を読む(番号)
                        .map_or_else(|| "無し".to_owned(), |残差| 残差.綴り()),
                    元の行空間の残差,
                }
            })
            .collect()
    }
}
