// 綴る件数の上限。全件を綴ると1本の走行で数十件になり、表へ写せる量を超える。
const 綴る件数の上限: usize = 12;

fn 測る二本() -> [許容差依存の診断の場合; 2] {
    [
        許容差依存の診断の場合 {
            静止摩擦係数の値,
            傾きの正接: 0.55,
            鉛直軸まわりの回しの度: 0.0,
            許容差の比: 1.0,
            行への適用規則: 接線の行への許容差の適用規則::許容差以下の接線変位の拘束行を追加しない,
            変更: 段階A1の場面からの一つの変更::細分数を十六にする,
        },
        許容差依存の診断の場合 {
            静止摩擦係数の値,
            傾きの正接: 0.50,
            鉛直軸まわりの回しの度: 0.0,
            許容差の比: 1.0,
            行への適用規則: 接線の行への許容差の適用規則::許容差以下の接線変位の拘束行を追加しない,
            変更: 段階A1の場面からの一つの変更::坂の面の法線の向きへ動かす {
                長さ: メートル::生成する(刻みを二倍にする長さ),
            },
        },
    ]
}

fn 一本の走行で解けなかった細分を綴る(場合: &許容差依存の診断の場合) {
    let 条件 = 場合.坂の場面の条件を組む();
    let 本数 = 分類を見る刻み数 * 場合.変更.一刻みの細分数();
    let mut 場面 = 場合.場面を組む();
    let (mut 件数, mut 接線の行が零の件数, mut 内側の行を含む件数) = (0, 0, 0);
    println!("[{}] 細分{本数}本を走らせて解けなかった細分を突き止める", 場合.見出し());
    for 番号 in 0..本数 {
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, false);
        for (反復の番号, 読み取り) in &記録.解けなかった連立方程式 {
            件数 += 1;
            接線の行が零の件数 += usize::from(読み取り.接線の行ごとの接線変位と許容差.is_empty());
            内側の行を含む件数 += usize::from(読み取り.許容差の内側の接線の行の本数() > 0);
            if 件数 <= 綴る件数の上限 {
                println!(
                    "  刻み{} 細分{番号} 反復{反復の番号} {}",
                    番号 / 場合.変更.一刻みの細分数(),
                    読み取り.綴り()
                );
            }
        }
    }
    println!("  要約 解けなかった件数={件数} うち接線の行が0本={接線の行が零の件数} うち許容差の内側の行を含む={内側の行を含む件数}");
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 行を積まない候補_解けなかった細分を突き止める() {
    for 場合 in 測る二本() {
        一本の走行で解けなかった細分を綴る(&場合);
    }
}
