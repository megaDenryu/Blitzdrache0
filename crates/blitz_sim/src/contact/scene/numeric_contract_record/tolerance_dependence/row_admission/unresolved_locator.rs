//! 段階A3の追加の計測: 設計候補(i')でも粘着の候補が解けずに残る細分を突き止める(Issue #59の第4段階。親の指示による)。
//! 候補(i')は「行を積まなければ解けずは0件になる」と予測されていたが、600刻みの延べで細分16本に50件、刻み2倍の
//! 平行移動に6件が残った(候補(i)の55件・8件からわずかに減っただけである)。この計器は、残った件がどの反復の
//! どの結末で起き、そのとき連立方程式に積まれていた接線の行が何本で、その行の C_t が δ より大きかったかを綴る。
//! 接線の行が0本なら、精度の不足は法線の行の側で起きており、接線の δ の話ではない。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use blitz_math::メートル;

