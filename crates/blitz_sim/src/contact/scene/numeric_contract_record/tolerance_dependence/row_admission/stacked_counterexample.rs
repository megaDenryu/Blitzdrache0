//! 段階A3の計測3: 重ねた反例(回し45度・細分16本・刻みが2倍になる平行移動・正接0.55)を、いまの本番・設計候補(i)・
//! 設計候補(i')の3つで測る(Issue #59の第4段階)。
//! 段階A2の6本はどれも1つだけを変えた場面であり、どの候補も保持した。この計測は、単独では保持する変更を3つ重ねて
//! 最初に崩れる候補を見る。副官の推測は「候補(i)で、細分2以降に残る接線変位 r を刻みの予測の変位 gs で割った値が
//! 回し0度の十数倍になり、細分1の比が0.6を超える」である。候補(i)の回し45度は細分7で 1.19e-6、細分63で 1.52e-6 と
//! 回し0度の 1e-7 より1桁大きく、細分16本では gs が4分の1になる。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use blitz_math::メートル;

use super::super::case::許容差依存の診断の場合;
use super::super::scene_variation::段階A1の場面からの一つの変更;
use super::{刻みを二倍にする長さ, 静止摩擦係数の値};
use crate::contact::normal_tangential_system::接線の行への許容差の当て方;

const 傾きの正接: f32 = 0.55;
const 鉛直軸まわりの回しの度: f32 = 45.0;
const 測る三つの当て方: [接線の行への許容差の当て方; 3] = [
    接線の行への許容差の当て方::右辺へ受理の倍率を掛けて残す,
    接線の行への許容差の当て方::右辺を零にする,
    接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする,
];

fn 場合を組む(行への許容差の当て方: 接線の行への許容差の当て方) -> 許容差依存の診断の場合 {
    許容差依存の診断の場合 {
        静止摩擦係数の値,
        傾きの正接,
        鉛直軸まわりの回しの度,
        許容差の比: 1.0,
        行への許容差の当て方,
        変更: 段階A1の場面からの一つの変更::細分数を十六にして坂の面の法線の向きへ動かす {
            長さ: メートル::生成する(刻みを二倍にする長さ),
        },
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 行を積まない候補_重ねた反例を三つの当て方で記録する() {
    for 行への許容差の当て方 in 測る三つの当て方 {
        let 記録 = super::一組を綴る(&場合を組む(行への許容差の当て方));
        println!(
            "  重ねた反例の残差 細分2の終わりΣ|Δt|={:.4e} 点ごと={:?} δt={:.4e}",
            記録[2].終わりの接線変位の合計(),
            記録[2].終わりの接線変位,
            記録[1].接線の行の許容差
        );
    }
}
