pub(super) const 静止摩擦係数の値: f32 = 0.6;
const 分類を見る刻み数: usize = 600;
// 細分2以降の残る接線変位を代表として綴る細分の番号。段階A1の表1・段階A2の表12と同じ並びである。
const 残る接線変位を綴る細分: [usize; 5] = [2, 3, 7, 19, 63];
// 坂の中心から接触点までの長さ。これだけ法線の向きへ動かすと接触点の座標が2倍になり、表現の刻みが2倍になる。
pub(super) const 刻みを二倍にする長さ: f32 = 20.4999;

/// 1組を64細分綴り、要約(段階A2の表12の列に、解いた回数の累計と候補(i)と有効集合が違う細分の数を足したもの)と
/// 600刻みの分類を綴る。
fn 一組を綴る(場合: &許容差依存の診断の場合) -> Vec<許容差依存の細分の記録> {
    let 記録 = super::一本の軌道を綴る(場合, false);
    要約を綴る(&記録);
    分類を綴る(場合);
    記録
}

fn 要約を綴る(記録: &[許容差依存の細分の記録]) {
    let 定まらなかった細分 = 記録
        .iter()
        .filter(|細分| 細分.反復ごと.iter().any(|反復| 反復.解けなかった集合の数 > 0))
        .count();
    let 解いた回数 = 記録.iter().fold(部分集合を解いた回数::零(), |合計, 細分| 合計.足す(細分.解いた回数));
    let 有効集合を比べた細分 = 記録.iter().filter(|細分| 細分.候補一と勝った有効集合が違うか.is_some()).count();
    let 有効集合が違う細分 = 記録.iter().filter(|細分| 細分.候補一と勝った有効集合が違うか == Some(true)).count();
    let 残る接線変位: Vec<String> = 残る接線変位を綴る細分
        .iter()
        .filter_map(|番号| 記録.get(*番号))
        .map(|細分| format!("細分{}={:.3e}", 細分.番号, 細分.終わりの接線変位の合計()))
        .collect();
    println!(
        "  要約 細分0の比={:.6} 細分1の比={:.6} 定まらなかった細分の数={定まらなかった細分} 滑走へ落ちた細分={:?} 終わりΣ|Δt| [{}] δt(細分1)={:.4e}",
        記録[0].最後の反復の後の円錐の比(),
        記録[1].最後の反復の後の円錐の比(),
        記録.iter().position(許容差依存の細分の記録::滑走中か),
        残る接線変位.join(" "),
        記録[1].接線の行の許容差
    );
    println!(
        "  要約(段階A3) 解いた回数の累計={} 全走査ならば={} 候補(i)と有効集合が違う細分={有効集合が違う細分} / 比べられた細分={有効集合を比べた細分}",
        解いた回数.階層の走査が解いた数(),
        解いた回数.全走査ならば解く数()
    );
}

fn 分類を綴る(場合: &許容差依存の診断の場合) {
    let 分類 = 場合.刻みを進めて分類する(分類を見る刻み数);
    println!(
        "  分類 [{}] {分類を見る刻み数}刻み {} 変位={:.3e} 解けず{} 置き直し{}",
        場合.見出し(),
        分類.綴り(),
        分類.坂に沿った変位(),
        分類.粘着の候補が解けなかった延べ数(),
        分類.錨を置き直した細分の延べ数()
    );
}
