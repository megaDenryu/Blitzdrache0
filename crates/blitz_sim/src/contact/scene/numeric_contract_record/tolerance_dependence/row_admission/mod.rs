//! Issue #59の第4段階の段階A3の計器。設計候補(i')「C_t の長さが δ の内側の接触点については接線の行を連立へ積まず、
//! 積んだ行の右辺は −C_t にする」を、段階A2の候補(i)と同じ軸で測り、候補(i)と対にする。
//! 候補(i)との違いは1つである。候補(i)は全部の点の行を積んで右辺だけを −C_t にするため、反復0が C_t を階数の残差の
//! 桁まで閉じた後の反復1で、擬似逆が ulp の桁の右辺を閉じようとして「表現の精度が不足した」を返す細分が残る。
//! 候補(i')はその点の行を積まないため、その状況そのものが起きないはずである。確かめていないのは、行を落とすと
//! 階数が下がって有効集合の探索が別の解を選ぶ細分が出るかどうかであり、この計器はそれを細分ごとに数える。
//! 実行は `cargo test -p blitz_sim --release 段階A3 -- --ignored --nocapture` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

