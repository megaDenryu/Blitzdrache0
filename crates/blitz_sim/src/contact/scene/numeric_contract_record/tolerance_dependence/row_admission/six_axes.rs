//! 段階A3の計測1: 設計候補(i')を、段階A2の表12と同じ6本の軸で測る(Issue #59の第4段階)。
//! 6本は、細分16本・回し30度・回し45度・刻みが2倍になる平行移動・休ませてから傾ける・静止摩擦係数0.8 である。
//! 予測は、細分1の比が正接そのものになること(候補(i)と同じ)と、候補(i)が残した「表現の精度が不足した」細分が
//! 0件になることである。候補(i)の実測は、600刻みの延べで細分16本に55件・休ませて傾けるに47件・平行移動に8件で
//! あった。確かめていないのは、行を落として階数が下がった連立方程式で有効集合の探索が別の解を選ぶ細分が出るかである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use blitz_math::メートル;

use super::super::case::許容差依存の診断の場合;
use super::super::scene_variation::段階A1の場面からの一つの変更;
use super::刻みを二倍にする長さ;
use crate::contact::normal_tangential_system::接線の行への許容差の適用規則;

// 候補(i')で測る1本。静止摩擦係数・正接・回しの度・場面の変更の4つで決まる。
struct 候補一ダッシュの一本 {
    静止摩擦係数の値: f32,
    傾きの正接: f32,
    鉛直軸まわりの回しの度: f32,
    変更: 段階A1の場面からの一つの変更,
}

impl 候補一ダッシュの一本 {
    fn 生成する(
        静止摩擦係数の値: f32, 傾きの正接: f32, 鉛直軸まわりの回しの度: f32, 変更: 段階A1の場面からの一つの変更
    ) -> Self {
        Self {
            静止摩擦係数の値,
            傾きの正接,
            鉛直軸まわりの回しの度,
            変更,
        }
    }

    /// 許容差の内側の点の行を積まず、積んだ行の右辺は −C_t にする、受理1倍の場合。
    fn 場合(&self) -> 許容差依存の診断の場合 {
        許容差依存の診断の場合 {
            静止摩擦係数の値: self.静止摩擦係数の値,
            傾きの正接: self.傾きの正接,
            鉛直軸まわりの回しの度: self.鉛直軸まわりの回しの度,
            許容差の比: 1.0,
            行への適用規則: 接線の行への許容差の適用規則::許容差以下の接線変位の拘束行を追加しない,
            変更: self.変更,
        }
    }
}

fn 測る六本() -> [候補一ダッシュの一本; 6] {
    [
        候補一ダッシュの一本::生成する(super::静止摩擦係数の値, 0.55, 0.0, 段階A1の場面からの一つの変更::細分数を十六にする),
        候補一ダッシュの一本::生成する(super::静止摩擦係数の値, 0.55, 30.0, 段階A1の場面からの一つの変更::無し),
        候補一ダッシュの一本::生成する(super::静止摩擦係数の値, 0.55, 45.0, 段階A1の場面からの一つの変更::無し),
        候補一ダッシュの一本::生成する(
            super::静止摩擦係数の値,
            0.50,
            0.0,
            段階A1の場面からの一つの変更::坂の面の法線の向きへ動かす {
                長さ: メートル::生成する(刻みを二倍にする長さ),
            },
        ),
        候補一ダッシュの一本::生成する(
            super::静止摩擦係数の値,
            0.55,
            0.0,
            段階A1の場面からの一つの変更::法線の逆向きの重力で休ませてから真の重力へ戻す,
        ),
        候補一ダッシュの一本::生成する(0.8, 0.55, 0.0, 段階A1の場面からの一つの変更::無し),
    ]
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 行を積まない候補_六つの軸で記録する() {
    for 一本 in 測る六本() {
        super::一組を綴る(&一本.場合());
    }
}
