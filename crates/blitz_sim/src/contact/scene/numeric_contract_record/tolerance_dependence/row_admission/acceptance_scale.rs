const 傾きの正接: f32 = 0.55;
const 振る受理の倍率: &[f32] = &[0.5, 1.0, 2.0];

fn 場合を組む(受理の倍率: f32) -> 許容差依存の診断の場合 {
    許容差依存の診断の場合 {
        静止摩擦係数の値,
        傾きの正接,
        鉛直軸まわりの回しの度: 0.0,
        許容差の比: 受理の倍率,
        行への許容差の当て方: 接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする,
        変更: 段階A1の場面からの一つの変更::無し,
    }
}

// 2本の軌道の64細分が全桁一致するか。比べるのは入口と終わりの接線変位・下り向きの速さ・行の許容差・反復ごとの
// 円錐の比と解けなかった集合の数である。1つでも違えば、違った最初の細分の番号を返す。
fn 全桁が違う最初の細分(一方: &[許容差依存の細分の記録], 他方: &[許容差依存の細分の記録]) -> Option<usize> {
    一方.iter().zip(他方.iter()).position(|(左, 右)| {
        左.入口の接線変位の合計 != 右.入口の接線変位の合計
            || 左.終わりの接線変位 != 右.終わりの接線変位
            || 左.下り向きの速さ != 右.下り向きの速さ
            || 左.接線の行の許容差 != 右.接線の行の許容差
            || 左.反復ごと.len() != 右.反復ごと.len()
            || 左.反復ごと.iter().zip(右.反復ごと.iter()).any(|(左の反復, 右の反復)| {
                左の反復.円錐の比() != 右の反復.円錐の比() || 左の反復.解けなかった集合の数 != 右の反復.解けなかった集合の数
            })
    })
}

