//! 正接0.55・回し0度・細分8本で64細分と600刻みの分類を綴り、3つの倍率の64細分が全桁一致するかを機械で確かめる。
//! 行を落とす閾値の δ には受理の倍率を掛けない(2つの δ は役目が違う)ため、予測は「全桁一致する」である。
//! 候補(i)の同じ計測(段階A2の表6)は3つの倍率で全桁一致し、600刻みで解けなかった細分の数だけが受理0.5倍で7件に
//! 増えた。候補(i')でその7件が消えるかが、この計測が答える問いである。
