//! 1倍と2倍の軌道の64細分の記録から要約を綴る工程(Issue #59の第4段階の許容差依存の診断)。
//! 綴るのは、計測点0の比例(2倍の軌道の終わりの接線変位と速さを1倍の同じ細分で割った比の範囲)、計測点5の増幅器
//! (細分1以降の反復1の後の比の最大と静止摩擦係数までの余裕)、2つの軌道で円錐の比が初めて0.01以上離れる細分の
//! 番号とその細分の採否が変わった固有の向き、計測点3の各列が解析の期待と一致しなかった細分の数、倍精度の刻みの
//! 行の残差の最大が実測の下限の定数を2倍以上外した細分の数である。合否は判定しない。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の数値契約の診断_2026-09-06.md`

#![cfg(test)]

use std::collections::BTreeMap;

use super::substep_record::許容差依存の細分の記録;
use super::実測の残差の下限メートル;

// 2つの軌道の円錐の比が離れたと見なす差。表の0.01刻みの走査と同じ大きさである。
const 比が離れたと見なす差: f64 = 0.01;

/// 1倍と2倍の軌道の記録の組。
pub(super) struct 二つの軌道の記録 {
    pub(super) 一倍: Vec<許容差依存の細分の記録>,
    pub(super) 二倍: Vec<許容差依存の細分の記録>,
}

impl 二つの軌道の記録 {
    pub(super) fn 要約を綴る(&self, 静止摩擦係数: f64) {
        self.比例を綴る();
        println!(
            "  要約 増幅器: 細分1以降の反復1の後の比の最大 1倍={:.6} 2倍={:.6} 静止摩擦係数{静止摩擦係数}までの余裕 1倍={:.6} 2倍={:.6}",
            比の最大を求める(&self.一倍),
            比の最大を求める(&self.二倍),
            静止摩擦係数 - 比の最大を求める(&self.一倍),
            静止摩擦係数 - 比の最大を求める(&self.二倍)
        );
        match self.比が初めて離れる細分() {
            Some(番号) => println!(
                "  要約 2つの軌道の比が初めて{比が離れたと見なす差}以上離れる細分={番号} その細分の採否が変わった向き={:?} 滑走中 1倍={} 2倍={}",
                self.一倍[番号].入口.as_ref().map(|入口| 入口.採否が変わった向き()),
                self.一倍[番号].滑走中か(),
                self.二倍[番号].滑走中か()
            ),
            None => println!("  要約 2つの軌道の比は64細分のあいだ{比が離れたと見なす差}以上離れない"),
        }
        self.計測点三の要約を綴る();
    }

    // 2倍の軌道の量を1倍の同じ細分で割った比の最小と最大(細分1以降。細分0は初めの食い込みを解く過渡である)。
    fn 比例を綴る(&self) {
        let 接線変位の比 = self.同じ細分の比(|記録| 記録.終わりの接線変位の合計());
        let 速さの比 = self.同じ細分の比(|記録| 記録.下り向きの速さ.abs());
        println!(
            "  要約 比例(2倍÷1倍、細分1以降): 終わりΣ|Δt|の比 最小={:.4} 最大={:.4} | |v↓|の比 最小={:.4} 最大={:.4}",
            範囲を求める(&接線変位の比).0,
            範囲を求める(&接線変位の比).1,
            範囲を求める(&速さの比).0,
            範囲を求める(&速さの比).1
        );
    }

    fn 同じ細分の比(&self, 量: fn(&許容差依存の細分の記録) -> f64) -> Vec<f64> {
        self.一倍
            .iter()
            .zip(self.二倍.iter())
            .skip(1)
            .filter(|(一倍, _)| 量(一倍) > 0.0)
            .map(|(一倍, 二倍)| 量(二倍) / 量(一倍))
            .collect()
    }

    fn 比が初めて離れる細分(&self) -> Option<usize> {
        self.一倍
            .iter()
            .zip(self.二倍.iter())
            .position(|(一倍, 二倍)| (一倍.最後の反復の後の円錐の比() - 二倍.最後の反復の後の円錐の比()).abs() >= 比が離れたと見なす差)
    }

    // 計測点3の列ごとに解析の期待と一致しなかった細分の数と、倍精度の刻みの行の残差の最大が定数を2倍以上外した細分の数。
    fn 計測点三の要約を綴る(&self) {
        let 入口: Vec<_> = self.一倍.iter().filter_map(|記録| 記録.入口.as_ref()).collect();
        let mut 不一致の数 = BTreeMap::new();
        for 列 in 入口.iter().flat_map(|入口| 入口.解析と一致しない列()) {
            *不一致の数.entry(列).or_insert(0usize) += 1;
        }
        let 外した数 = 入口
            .iter()
            .filter_map(|入口| 入口.倍精度の刻みの行ごとの残差の最大)
            .filter(|残差| *残差 > 実測の残差の下限メートル * 2.0 || *残差 < 実測の残差の下限メートル / 2.0)
            .count();
        let 定まらず = 入口.iter().filter(|入口| 入口.倍精度の刻みの行ごとの残差の最大.is_none()).count();
        println!(
            "  要約 計測点3: 解析と一致しない細分の数={不一致の数:?} 倍精度の刻みの行の残差の最大が{実測の残差の下限メートル:.1e}を2倍以上外した細分={外した数} 倍精度の刻みが定まらなかった細分={定まらず} 入口を読んだ細分={}",
            入口.len()
        );
    }
}

fn 比の最大を求める(記録: &[許容差依存の細分の記録]) -> f64 {
    記録
        .iter()
        .skip(1)
        .map(許容差依存の細分の記録::最後の反復の後の円錐の比)
        .fold(f64::MIN, f64::max)
}

fn 範囲を求める(並び: &[f64]) -> (f64, f64) {
    (
        並び.iter().copied().fold(f64::MAX, f64::min),
        並び.iter().copied().fold(f64::MIN, f64::max),
    )
}
