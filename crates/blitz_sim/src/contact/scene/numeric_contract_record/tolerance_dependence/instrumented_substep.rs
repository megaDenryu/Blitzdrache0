//! 記録しながら細分1本を進める工程(Issue #59の第4段階の許容差依存の診断)。本番の試験用の工程`一細分進める`と
//! 同じ部品を同じ順で呼び、部品の間に読むだけの口(状態を書き換えない)を挟む。したがって進めた後の配置と運動状態は
//! `一細分進める`と1ビットも違わない。その一致は`fidelity_tests`が固定し、通らない限り表の値は本番の値でない。
//! `cone_breach_record/instrumented_substep`と違い、細分の残り(速度の再構成・速度段階・履歴の書き戻し)も本番と同じに
//! 行い、場面を進める。細分ごとに場面を組み直さないため、64細分の読み取りが本数に比例する費用で済む。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::anchor_displacement::{合計を求める, 錨からの接線変位の長さの並び};
use super::iteration_reading::反復の後の読み取り;
use super::substep_record::許容差依存の細分の記録;
use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::normal_tangential_system::部分集合を解いた回数;
use crate::contact::scene::slope_geometry::坂の場面の条件;
use crate::contact::scene::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_body::一刻みの入力;

impl 一つの箱と静的な直方体の場面 {
    /// 次の1細分を本番と同じ順で進めながら記録を綴る。入口を読むかが真なら第一反復の入口の読み取りも持つ。
    pub(super) fn 記録しながら一細分進める(
        &mut self,
        番号: usize,
        条件: &坂の場面の条件,
        入口を読むか: bool,
    ) -> 許容差依存の細分の記録 {
        let (前の状態, mut 予測, 予測の運動状態) =
            self.予測器
                .動的剛体を予測する(&self.箱の配置, &self.箱の運動状態, &self.箱の質量特性, &一刻みの入力::無し());
        let mut バッチ = self.接触拘束のバッチを組む(&予測);
        let 開始した接触点の数 = self.履歴の記録を引き継ぐ(&mut バッチ, &前の状態.保存した配置());
        let 予測の前の法線相対速度 = self.予測の前の法線相対速度を測る(&バッチ, &予測, 予測の運動状態);
        let 入口 = 入口を読むか.then(|| self.第一反復の入口を読む(バッチ.剛体と静的世界の接触拘束(), 予測.配置()));
        let 接線の行の許容差 = self.接線の行の許容差を読む(バッチ.剛体と静的世界の接触拘束(), 予測.配置());
        let 候補一と勝った有効集合が違うか = self.候補一と勝った有効集合が違うか(バッチ.剛体と静的世界の接触拘束(), 予測.配置());
        let 入口の接線変位の合計 = 合計を求める(&錨からの接線変位の長さの並び(
            バッチ.剛体と静的世界の接触拘束(),
            予測.配置(),
        ));
        let mut 反復ごと = Vec::new();
        let mut 解いた回数 = 部分集合を解いた回数::零();
        let mut 解けなかった連立方程式 = Vec::new();
        for 反復の番号 in 0..self.解く品質.位置の反復回数() {
            let 結果 = self.一回反復する(&mut バッチ, 予測);
            解けなかった連立方程式.extend(結果.解けなかった連立方程式.into_iter().map(|読み取り| (反復の番号, 読み取り)));
            self.粘着の候補が解けなかった接触点集合の延べ数 += 結果.粘着の候補が解けなかった接触点集合の数;
            解いた回数 = 解いた回数.足す(結果.解いた回数);
            予測 = 結果.予測;
            反復ごと.push(反復の後の読み取り::接触点集合と配置から読む(
                バッチ.剛体と静的世界の接触拘束(),
                予測.配置(),
                結果.粘着の候補が解けなかった接触点集合の数,
                結果.表現の精度が不足した接触点集合の数,
            ));
        }
        self.錨を置き直した細分を数える(&バッチ);
        let 終わりの接線変位 = 錨からの接線変位の長さの並び(バッチ.剛体と静的世界の接触拘束(), 予測.配置());
        let 再構成した運動状態 = 前の状態.確定した配置から速度を再構成する(予測.配置(), self.刻み幅);
        self.箱の配置 = *予測.配置();
        let 速度段階 = self.速度段階を適用する(&バッチ, &予測の前の法線相対速度, 再構成した運動状態);
        self.箱の運動状態 = 速度段階.運動状態;
        self.直前の細分の観測 = self.細分の観測を作る(&バッチ, &予測, 開始した接触点の数, &速度段階);
        let 終わりの項目: Vec<_> = バッチ
            .剛体と静的世界の接触拘束()
            .iter()
            .map(剛体と静的世界の接触拘束::細分の終わりの履歴の項目)
            .collect();
        self.履歴.細分の終わりの記録で置き換える(&終わりの項目).unwrap();
        許容差依存の細分の記録 {
            番号,
            入口の接線変位の合計,
            反復ごと,
            終わりの接線変位,
            下り向きの速さ: f64::from(self.下り向きの速さ(条件)),
            接線の行の許容差,
            入口,
            解いた回数,
            候補一と勝った有効集合が違うか,
            解けなかった連立方程式,
        }
    }
}
