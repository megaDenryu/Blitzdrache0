//! 段階A2の計測が段階A1の場面(正接0.55・回し0度・8細分・鉛直の重力)から1つだけ変える点(Issue #59の第4段階)。
//! 1本の計測は場面を既定から1つだけ変えることを、4枝の列挙で表す。2つ以上を同時に変えると、分類が動いたときに
//! どの変更が効いたかを分けられないためである。許容差の当て方(受理の倍率と右辺の δ の扱い)は場面の変更ではなく
//! 解法の取り決めであるため、この列挙には入れず、場合が別の欄で持って組み立ての指定へ渡す。
//! 「休ませてから傾ける」を水平の床で作らないのは、水平の床では接触点の座標が ±0.5 メートルになり接線の行の
//! 許容差 δ_t が段階A1の30分の1へ落ちるためである。坂の幾何は段階A1のままにし、重力を坂の面の法線の逆向きに
//! 与えて休ませてから鉛直へ戻すと、座標も δ_t も段階A1と同じまま「接線の荷重が掛かり始める細分」だけを作れる。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use blitz_math::メートル;

use crate::contact::normal_tangential_system::試験の許容差の当て方;
use crate::contact::scene::slope_geometry::坂の場面の条件;
use crate::contact::scene::slope_scene_spec::{
    向きへ掛かる重力, 坂の場面の一刻みの細分数, 坂の場面の組み立ての指定, 鉛直下向きの重力
};
use crate::contact::scene::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_xpbd::{ジャイロ項の扱い, 細分の予測器};

// 法線の逆向きの重力で休ませる細分の本数。段階A1の表1では細分2以降で速度が零へ戻るため、3刻みぶんで定常に足りる。
pub(super) const 傾ける前に休ませる細分の本数: usize = 24;

/// 段階A1の場面から1つだけ変える点。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) enum 段階A1の場面からの一つの変更 {
    無し,
    細分数を十六にする,
    坂の面の法線の向きへ動かす { 長さ: メートル },
    法線の逆向きの重力で休ませてから真の重力へ戻す,
}

impl 段階A1の場面からの一つの変更 {
    /// この変更を1つだけ加えた組み立ての指定。許容差の当て方はどの変更でも渡した値である。
    pub(super) fn 組み立ての指定を作る(
        &self,
        条件: &坂の場面の条件,
        許容差の当て方: 試験の許容差の当て方,
    ) -> 坂の場面の組み立ての指定 {
        let mut 指定 = 坂の場面の組み立ての指定 {
            試験の許容差の当て方: 許容差の当て方,
            ..坂の場面の組み立ての指定::既定()
        };
        match self {
            Self::無し => {}
            Self::細分数を十六にする => 指定.一刻みの細分数 = 坂の場面の一刻みの細分数::十六本,
            Self::坂の面の法線の向きへ動かす { 長さ } => 指定.法線の向きへ動かす長さ = *長さ,
            Self::法線の逆向きの重力で休ませてから真の重力へ戻す => {
                指定.重力 = 向きへ掛かる重力(条件.坂の面の法線().逆を向く方向());
            }
        }
        指定
    }

    /// 組んだ場面を計測の始点へ進める。休ませる変更だけが休止の細分を進めて重力を鉛直へ戻し、他は何もしない。
    pub(super) fn 組んだ場面を計測の始点へ進める(&self, 場面: &mut 一つの箱と静的な直方体の場面) {
        if *self != Self::法線の逆向きの重力で休ませてから真の重力へ戻す {
            return;
        }
        場面.細分を進める(傾ける前に休ませる細分の本数);
        場面.予測器 = 細分の予測器::生成する(場面.刻み幅, 鉛直下向きの重力(), ジャイロ項の扱い::陰的に一段解く);
    }

    /// この変更の場面で基本刻み1本に当たる細分の本数。
    pub(super) fn 一刻みの細分数(&self) -> usize {
        match self {
            Self::細分数を十六にする => 坂の場面の一刻みの細分数::十六本.本数(),
            Self::無し | Self::坂の面の法線の向きへ動かす { .. } | Self::法線の逆向きの重力で休ませてから真の重力へ戻す => {
                坂の場面の一刻みの細分数::八本.本数()
            }
        }
    }

    /// 見出しへ足す綴り。変更が無ければ空である。
    pub(super) fn 綴り(&self) -> String {
        match self {
            Self::無し => String::new(),
            Self::細分数を十六にする => "_細分16本".to_owned(),
            Self::坂の面の法線の向きへ動かす { 長さ } => format!("_移動{}", 長さ.値()),
            Self::法線の逆向きの重力で休ませてから真の重力へ戻す => "_休ませて傾ける".to_owned(),
        }
    }
}
