//! 指定の配置で接触点ごとに錨からの接線変位の長さを読む工程(Issue #59の第4段階の許容差依存の診断)。
//! 式は判断13の Δ_t = (a_A − a_B) − ((a_A − a_B)·n) n であり、判断24の解法上の残差もこの量である。
//! 接触点集合と配置を対等に読み、どちらも主語にできないためレシーバを持たない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 解法上の残差を、実際に生じた物理変位と同一視して物理速度へ再注入しない」

#![cfg(test)]

use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::rigid_body::配置;

/// 接触点ごとの、指定の配置での錨からの接線変位の長さ(メートル)。並びは接触点集合の点の番号と同じである。
pub(super) fn 錨からの接線変位の長さの並び(接触点集合: &[剛体と静的世界の接触拘束], 配置: &配置) -> Vec<f64> {
    接触点集合
        .iter()
        .map(|拘束| {
            let 錨 = 拘束.静止摩擦の錨();
            let 接線変位 =
                (配置.局所点の世界位置(錨.第1の参加者の重心局所点()) - 錨.第2の参加者から見た点()).方向の成分を除く(拘束.引数().接触法線);
            f64::from(接線変位.長さ().値())
        })
        .collect()
}

/// 並びの合計。表の1行が点ごとの値と合計の両方を出すためにある。
pub(super) fn 合計を求める(並び: &[f64]) -> f64 {
    並び.iter().sum()
}
