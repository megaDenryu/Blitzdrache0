//! 段階A2の計測(う): 回し30度と45度の計測点1(Issue #59の第4段階。候補Eを正当に外すための計測)。正接0.55で、1倍の軌道の
//! 同じ配置に1倍と2倍の許容差を当て、固有の向きごとの採否が変わった向きの数を細分0〜63で数える。0本なら候補E
//! (擬似逆の受理条件)は回しによらず効かない。細分1の比と δt も添え、増幅器の式が回しでどう動くかを読めるようにする。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::scene_variation::段階A1の場面からの一つの変更;
use super::super::並べる細分の本数;
use super::場合を組む;

const 傾きの正接: f32 = 0.55;
const 振る鉛直軸まわりの回しの度: [f32; 2] = [30.0, 45.0];

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 五つの軸_回し三十度と四十五度の採否を記録する() {
    for 回しの度 in 振る鉛直軸まわりの回しの度 {
        let 場合 = 場合を組む(傾きの正接, 回しの度, 1.0, 段階A1の場面からの一つの変更::無し);
        let 条件 = 場合.坂の場面の条件を組む();
        let mut 場面 = 場合.場面を組む();
        println!("[{}] 計測点1 細分0〜{}", 場合.見出し(), 並べる細分の本数 - 1);
        let mut 採否が変わった細分の数 = 0;
        for 番号 in 0..並べる細分の本数 {
            let 記録 = 場面.記録しながら一細分進める(番号, &条件, true);
            let 入口 = 記録.入口.as_ref().unwrap();
            let 変わった向き = 入口.採否が変わった向き();
            採否が変わった細分の数 += usize::from(!変わった向き.is_empty());
            println!(
                "  細分{番号} 採否が変わった向き={変わった向き:?} 有効集合 1倍={} 2倍={} 反復1後の比={:.6} δt={:.4e}",
                入口.一倍の内訳.as_ref().map_or("定まらず".to_owned(), |内訳| 内訳.有効集合の綴り()),
                入口.二倍の内訳.as_ref().map_or("定まらず".to_owned(), |内訳| 内訳.有効集合の綴り()),
                記録.最後の反復の後の円錐の比(),
                記録.接線の行の許容差
            );
        }
        println!("  要約 回し{回しの度}度 採否が変わった向きを持つ細分の数={採否が変わった細分の数}(64細分中)");
    }
}
