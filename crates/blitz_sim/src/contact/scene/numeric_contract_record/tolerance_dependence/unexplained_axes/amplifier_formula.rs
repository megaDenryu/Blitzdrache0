//! 段階A1が立てた増幅器の式(Issue #59の第4段階)。細分1の円錐の比の予測 tanθ (1 + m δ ÷ (g sinθ h²)) と、
//! 傾けた1本目の細分の予測 tanθ (1 − δ ÷ (g sinθ h²)) を答える。式が持つのは坂の正接と細分の刻み幅であり、
//! δ(接線の行の許容差)と m(倍率)は計測ごとに違うため引数で受ける。計器は予測と実測を並べて綴り、当たり外れを
//! 記録が判定する。この型が合否を持つことはない。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use crate::contact::scene::slope_geometry::重力の大きさ;

/// 増幅器の式。
pub(super) struct 増幅器の式 {
    傾きの正接: f64,
    細分の刻み幅の秒: f64,
}

impl 増幅器の式 {
    pub(super) fn 正接と刻み幅から生成する(傾きの正接: f32, 細分の刻み幅の秒: f32) -> Self {
        Self {
            傾きの正接: f64::from(傾きの正接),
            細分の刻み幅の秒: f64::from(細分の刻み幅の秒),
        }
    }

    /// 静止した箱が1細分に重力で坂を下る予測の変位 g sinθ h²。
    pub(super) fn 一細分の予測の接線変位(&self) -> f64 {
        let 正弦 = self.傾きの正接 / (1.0 + self.傾きの正接 * self.傾きの正接).sqrt();
        f64::from(重力の大きさ) * 正弦 * self.細分の刻み幅の秒 * self.細分の刻み幅の秒
    }

    /// 接線の荷重が掛かり始めた次の細分(段階A1の細分1)の比の予測 tanθ (1 + m δ ÷ (g sinθ h²))。
    pub(super) fn 二本目の細分の比の予測(&self, 接線の行の許容差: f64, 倍率: f64) -> f64 {
        self.傾きの正接 * (1.0 + 倍率 * 接線の行の許容差 / self.一細分の予測の接線変位())
    }

    /// 接線の荷重が掛かり始めた細分そのものの比の予測 tanθ (1 − m δ ÷ (g sinθ h²))。法線の過渡が無い場面でだけ
    /// 実測と比べられる(段階A1の細分0は初めの食い込みを解く Σλ_n の過渡が分母に入るため比べられない)。
    pub(super) fn 一本目の細分の比の予測(&self, 接線の行の許容差: f64, 倍率: f64) -> f64 {
        self.傾きの正接 * (1.0 - 倍率 * 接線の行の許容差 / self.一細分の予測の接線変位())
    }
}
