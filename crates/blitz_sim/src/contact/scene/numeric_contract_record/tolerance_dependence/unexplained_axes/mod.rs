/// 静止摩擦係数0.6・右辺の δ を残す、段階A1と同じ解法の場合。
fn 場合を組む(
    傾きの正接: f32,
    鉛直軸まわりの回しの度: f32,
    許容差の比: f32,
    変更: 段階A1の場面からの一つの変更,
) -> 許容差依存の診断の場合 {
    許容差依存の診断の場合 {
        静止摩擦係数の値,
        傾きの正接,
        鉛直軸まわりの回しの度,
        許容差の比,
        右辺の許容差の扱い: 接線の行の右辺の許容差の扱い::受理の倍率を掛けて残す,
        変更,
    }
}

/// 1組を64細分綴り、その要約(細分1の比・定まらなかった細分の数・滑走へ落ちた細分・残る接線変位)と600刻みの分類を綴る。
fn 一組を綴る(場合: &許容差依存の診断の場合) -> Vec<許容差依存の細分の記録> {
    let 記録 = super::一本の軌道を綴る(場合, false);
    要約を綴る(&記録);
    let 分類 = 場合.刻みを進めて分類する(分類を見る刻み数);
    println!(
        "  分類 [{}] {分類を見る刻み数}刻み {} 変位={:.3e} 解けず{} 置き直し{}",
        場合.見出し(),
        分類.綴り(),
        分類.坂に沿った変位(),
        分類.粘着の候補が解けなかった延べ数(),
        分類.錨を置き直した細分の延べ数()
    );
    記録
}

fn 要約を綴る(記録: &[許容差依存の細分の記録]) {
    let 定まらなかった細分 = 記録
        .iter()
        .filter(|細分| 細分.反復ごと.iter().any(|反復| 反復.解けなかった集合の数 > 0))
        .count();
    let 滑走へ落ちた細分 = 記録.iter().position(許容差依存の細分の記録::滑走中か);
    let 残る接線変位: Vec<String> = 残る接線変位を綴る細分
        .iter()
        .filter_map(|番号| 記録.get(*番号))
        .map(|細分| format!("細分{}={:.3e}", 細分.番号, 細分.終わりの接線変位の合計()))
        .collect();
    println!(
        "  要約 細分0の比={:.6} 細分1の比={:.6} 定まらなかった細分の数={定まらなかった細分} 滑走へ落ちた細分={:?} 終わりΣ|Δt| [{}] δt(細分1)={:.4e}",
        記録[0].最後の反復の後の円錐の比(),
        記録[1].最後の反復の後の円錐の比(),
        滑走へ落ちた細分,
        残る接線変位.join(" "),
        記録[1].接線の行の許容差
    );
}
