//! 段階A2の計測(お): 刻みが2倍になる平行移動(動かす長さ 20.4999 m・回し0度・正接0.50)の1組の細分0と1(Issue #59の
//! 第4段階)。第3段階の表5で滑走のまま残った組であり、細分0の終わりの残る接線変位と v↓h ÷ δ_t、細分1の入口 Σ|Δt| と比を
//! 出し、その位置の δ'(列 δt)から式 tanθ (1 + δ' ÷ gs) で予測した比と比べる。一致すれば平行移動の未達は同じ増幅器の姿である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use blitz_math::メートル;

use super::super::scene_variation::段階A1の場面からの一つの変更;
use super::amplifier_formula::増幅器の式;
use super::場合を組む;

const 傾きの正接: f32 = 0.50;
// 坂の中心から接触点までの長さ。これだけ法線の向きへ動かすと接触点の座標が2倍になり、表現の刻みが2倍になる。
const 刻みを二倍にする長さ: f32 = 20.4999;
const 細分の刻み幅の秒: f32 = 1.0 / 480.0;

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 五つの軸_刻み二倍の平行移動の一組を記録する() {
    let 場合 = 場合を組む(
        傾きの正接,
        0.0,
        1.0,
        段階A1の場面からの一つの変更::坂の面の法線の向きへ動かす {
            長さ: メートル::生成する(刻みを二倍にする長さ),
        },
    );
    let 記録 = super::一組を綴る(&場合);
    let 式 = 増幅器の式::正接と刻み幅から生成する(傾きの正接, 細分の刻み幅の秒);
    println!(
        "式の予測(移動{刻みを二倍にする長さ}) gs={:.4e} δ'(細分0)={:.4e} δ'(細分1)={:.4e} 細分1の入口Σ|Δt|の予測 4(gs+2δ')={:.4e} 実測={:.4e} 細分1の比の予測={:.6} 実測={:.6} 細分0の終わりΣ|Δt|={:.4e} v↓h/δt={:.4}",
        式.一細分の予測の接線変位(),
        記録[0].接線の行の許容差,
        記録[1].接線の行の許容差,
        4.0 * (式.一細分の予測の接線変位() + 2.0 * 記録[1].接線の行の許容差),
        記録[1].入口の接線変位の合計,
        式.二本目の細分の比の予測(記録[1].接線の行の許容差, 1.0),
        記録[1].最後の反復の後の円錐の比(),
        記録[0].終わりの接線変位の合計(),
        記録[0].速さの一細分の変位と許容差の比(f64::from(細分の刻み幅の秒))
    );
}
