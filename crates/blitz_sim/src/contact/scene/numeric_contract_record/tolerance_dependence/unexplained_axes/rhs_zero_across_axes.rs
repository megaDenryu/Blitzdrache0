//! 段階A2の追加の計測: 設計候補(i)(接線の行の右辺の δ を零、受理の δ は1倍)を、式が説明していない5つの軸で測る
//! (Issue #59の第4段階。副官の反論による追加)。(1)細分16本・正接0.55・回し0度、(2)回し30度と45度・正接0.55、
//! (3)刻みが2倍になる平行移動・正接0.50、(4)休ませてから傾ける・正接0.55、(5)静止摩擦係数0.8・正接0.55 の6本である。
//! 各本で細分1の比・600刻みの分類・有効集合が定まらなかった細分の数(64細分と600刻み)・細分2以降に残る接線変位を綴る。
//! (1)は式の外挿(比 tanθ (1 + 2r ÷ gs) = 0.563 で保持)と比べる。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use blitz_math::メートル;

use super::super::case::許容差依存の診断の場合;
use super::super::scene_variation::段階A1の場面からの一つの変更;
use super::amplifier_formula::増幅器の式;
use crate::contact::normal_tangential_system::接線の行への許容差の適用規則;

const 十六本の細分の刻み幅の秒: f32 = 1.0 / 960.0;
// 倍精度でも連立の階数で満たせずに残る行の残差の代表値(段階A1の表2の勝った有効集合の残差の最大の上端)。
const 階数で満たせない残差メートル: f64 = 6.0e-8;
// 坂の中心から接触点までの長さ。これだけ法線の向きへ動かすと接触点の座標が2倍になり、表現の刻みが2倍になる。
const 刻みを二倍にする長さ: f32 = 20.4999;

// 候補(i)で測る1本。静止摩擦係数・正接・回しの度・場面の変更の4つで決まる。
struct 候補一の一本 {
    静止摩擦係数の値: f32,
    傾きの正接: f32,
    鉛直軸まわりの回しの度: f32,
    変更: 段階A1の場面からの一つの変更,
}

impl 候補一の一本 {
    fn 生成する(
        静止摩擦係数の値: f32, 傾きの正接: f32, 鉛直軸まわりの回しの度: f32, 変更: 段階A1の場面からの一つの変更
    ) -> Self {
        Self {
            静止摩擦係数の値,
            傾きの正接,
            鉛直軸まわりの回しの度,
            変更,
        }
    }

    /// 右辺の δ を零にし受理の δ は1倍の、候補(i)の場合。
    fn 場合(&self) -> 許容差依存の診断の場合 {
        許容差依存の診断の場合 {
            静止摩擦係数の値: self.静止摩擦係数の値,
            傾きの正接: self.傾きの正接,
            鉛直軸まわりの回しの度: self.鉛直軸まわりの回しの度,
            許容差の比: 1.0,
            行への適用規則: 接線の行への許容差の適用規則::全部の拘束行を追加し右辺から許容差を外す,
            変更: self.変更,
        }
    }
}

fn 測る六本() -> [候補一の一本; 6] {
    [
        候補一の一本::生成する(0.6, 0.55, 0.0, 段階A1の場面からの一つの変更::細分数を十六にする),
        候補一の一本::生成する(0.6, 0.55, 30.0, 段階A1の場面からの一つの変更::無し),
        候補一の一本::生成する(0.6, 0.55, 45.0, 段階A1の場面からの一つの変更::無し),
        候補一の一本::生成する(
            0.6,
            0.50,
            0.0,
            段階A1の場面からの一つの変更::坂の面の法線の向きへ動かす {
                長さ: メートル::生成する(刻みを二倍にする長さ),
            },
        ),
        候補一の一本::生成する(
            0.6,
            0.55,
            0.0,
            段階A1の場面からの一つの変更::法線の逆向きの重力で休ませてから真の重力へ戻す,
        ),
        候補一の一本::生成する(0.8, 0.55, 0.0, 段階A1の場面からの一つの変更::無し),
    ]
}

