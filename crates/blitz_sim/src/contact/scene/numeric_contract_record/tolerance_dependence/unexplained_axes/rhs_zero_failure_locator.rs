//! 段階A2の追加の計測: 右辺の δ を零にして受理の δ を0.5倍にした組(正接0.55・回し0度)で、600刻みのうち粘着の候補が
//! 解けなかった細分を突き止め、そのときの解の結末(相補条件を満たす有効集合が無いのか、表現の精度が不足したのか)と、
//! 全部の点を有効にした連立方程式の固有の向きごとの採否と行ごとの残差を綴る(Issue #59の第4段階。副官の反論による追加)。
//! 1つ目の走行で解けなかった細分の番号を集め、2つ目の走行で同じ場面をその細分まで進めて入口を読む。1つ目の走行で毎細分
//! 入口を読まないのは、入口の読み取りが倍精度の参照を3回解くため4800細分では重いからである。
//! 受理1倍と2倍は600刻みで0件であるため、この計測は「右辺の δ を外したときに受理の δ が小さいと何が起きるか」の観測である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::case::許容差依存の診断の場合;
use super::super::scene_variation::段階A1の場面からの一つの変更;
use super::super::substep_record::許容差依存の細分の記録;
use super::{分類を見る刻み数, 静止摩擦係数の値};
use crate::contact::normal_tangential_system::接線の行への許容差の適用規則;

const 傾きの正接: f32 = 0.55;
const 受理の倍率: f32 = 0.5;

fn 解けなかった反復の番号(記録: &許容差依存の細分の記録) -> Vec<usize> {
    記録
        .反復ごと
        .iter()
        .enumerate()
        .filter(|(_, 反復)| 反復.解けなかった集合の数 > 0)
        .map(|(番号, _)| 番号)
        .collect()
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 五つの軸_右辺零で受理零点五倍の解けなかった細分を突き止める() {
    let 場合 = 許容差依存の診断の場合 {
        静止摩擦係数の値,
        傾きの正接,
        鉛直軸まわりの回しの度: 0.0,
        許容差の比: 受理の倍率,
        行への適用規則: 接線の行への許容差の適用規則::全部の拘束行を追加し右辺から許容差を外す,
        変更: 段階A1の場面からの一つの変更::無し,
    };
    let 条件 = 場合.坂の場面の条件を組む();
    let 本数 = 分類を見る刻み数 * 場合.変更.一刻みの細分数();
    let mut 場面 = 場合.場面を組む();
    let mut 解けなかった細分 = Vec::new();
    for 番号 in 0..本数 {
        let 記録 = 場面.記録しながら一細分進める(番号, &条件, false);
        let 反復 = 解けなかった反復の番号(&記録);
        if 反復.is_empty() {
            continue;
        }
        解けなかった細分.push(番号);
        println!(
            "[{}] 刻み{} 細分{番号} 解けなかった反復={反復:?} 精度不足の内訳={:?} 入口Σ|Δt|={:.4e} 反復1後の比={:.6}",
            場合.見出し(),
            番号 / 場合.変更.一刻みの細分数(),
            記録.反復ごと.iter().map(|反復| 反復.表現の精度が不足した集合の数).collect::<Vec<_>>(),
            記録.入口の接線変位の合計,
            記録.最後の反復の後の円錐の比()
        );
    }
    println!("  要約 {}刻みで解けなかった細分の数={}", 分類を見る刻み数, 解けなかった細分.len());
    let mut 二回目 = 場合.場面を組む();
    for 番号 in 0..本数 {
        let 記録 = 二回目.記録しながら一細分進める(番号, &条件, 解けなかった細分.contains(&番号));
        let Some(入口) = 記録.入口 else { continue };
        println!(
            "  細分{番号}の入口 場面の適用規則の結末={} 受理1倍={} 受理2倍={}",
            入口.場面の適用規則の結末の綴り,
            入口.単精度の一倍.結末の綴り(),
            入口.単精度の二倍.結末の綴り()
        );
        let 内訳 = &入口.場面の適用規則の全点の内訳;
        println!(
            "    全点の内訳 有効集合={} 残差={:?} 捨てた右辺={:?} 許容差={:?}",
            内訳.有効集合の綴り(),
            小数で綴る(&内訳.行ごとの残差),
            小数で綴る(&内訳.行ごとの許容差の内側として捨てた右辺),
            小数で綴る(&内訳.行ごとの解けたと見なす許容差)
        );
        for (k, 向き) in 内訳.固有の向きごと.iter().enumerate() {
            println!(
                "    向き{k} λ={:.4e} vᵀb={:.4e} δ={:.4e} 採否={:?}",
                向き.固有値, 向き.右辺の射影, 向き.許容差の射影, 向き.捨てた理由
            );
        }
    }
}

fn 小数で綴る(並び: &[f32]) -> Vec<String> {
    並び.iter().map(|値| format!("{値:.3e}")).collect()
}
