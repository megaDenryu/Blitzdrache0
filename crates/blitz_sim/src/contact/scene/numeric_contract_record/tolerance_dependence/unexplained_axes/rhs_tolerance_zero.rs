//! 段階A2の計測(あ): 接線の行の右辺の δ を零にし、擬似逆の受理の δ だけを0.5倍・1倍・2倍に振る(Issue #59の第4段階。
//! 設計候補(i)の一次計測)。正接0.55・回し0度で64細分と600刻みの分類を綴る。式の予測は、右辺の δ が無いため
//! 細分1の比が tanθ (1 + 2r ÷ (g sinθ h²)) ≈ 0.553(r は連立の階数で満たせない残差 ≈ 6e-8 m)であり、細分2以降の
//! 残る接線変位は零へ向かう。受理の倍率は右辺に入らないため、3つの倍率で比は変わらないはずである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::case::許容差依存の診断の場合;
use super::super::scene_variation::段階A1の場面からの一つの変更;
use super::amplifier_formula::増幅器の式;
use super::静止摩擦係数の値;
use crate::contact::normal_tangential_system::接線の行の右辺の許容差の扱い;

const 傾きの正接: f32 = 0.55;
const 振る受理の倍率: &[f32] = &[0.5, 1.0, 2.0];
// 倍精度でも連立の階数で満たせずに残る行の残差の代表値(段階A1の表2の勝った有効集合の残差の最大の上端)。
const 階数で満たせない残差メートル: f64 = 6.0e-8;

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 五つの軸_右辺の許容差を零にして受理だけを振った一組を記録する() {
    let 式 = 増幅器の式::正接と刻み幅から生成する(傾きの正接, 1.0 / 480.0);
    println!(
        "式の予測 細分1の比 = tanθ (1 + 2r ÷ gs) = {:.6}(r={階数で満たせない残差メートル:.1e}, gs={:.4e})",
        式.二本目の細分の比の予測(階数で満たせない残差メートル, 2.0),
        式.一細分の予測の接線変位()
    );
    for 受理の倍率 in 振る受理の倍率.iter().copied() {
        let 場合 = 許容差依存の診断の場合 {
            静止摩擦係数の値,
            傾きの正接,
            鉛直軸まわりの回しの度: 0.0,
            許容差の比: 受理の倍率,
            右辺の許容差の扱い: 接線の行の右辺の許容差の扱い::零にする,
            変更: 段階A1の場面からの一つの変更::無し,
        };
        super::一組を綴る(&場合);
    }
}
