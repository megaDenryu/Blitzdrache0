//! 段階A2の計測(え): 法線の逆向きの重力で休ませてから真の重力へ戻す1組(Issue #59の第4段階。反例)。正接0.55・回し0度で、
//! 許容差1倍と2倍のそれぞれについて、重力を戻した後の64細分と600刻みの分類を綴る。細分の番号は重力を戻した細分を0とする。
//! 委譲の文の予測は「増幅器は現れない(比は最初から tanθ)」である。式から導いた予測はそれと違い、増幅器の入口は
//! 「錨からの接線変位が零の状態から接線の荷重が掛かり始める細分」であって初めの食い込みの過渡ではないため、
//! 戻した1本目の比 = tanθ (1 − δ ÷ gs) ≈ 0.527、2本目 = tanθ (1 + m δ ÷ gs) ≈ 0.597(2倍で 0.644 → 滑走)である。
//! この計測が確かめるのは「法線の過渡は増幅器に無関係である」ことである(親の裁定、2026-09-09)。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::scene_variation::{傾ける前に休ませる細分の本数, 段階A1の場面からの一つの変更};
use super::amplifier_formula::増幅器の式;
use super::場合を組む;

const 傾きの正接: f32 = 0.55;
const 細分の刻み幅の秒: f32 = 1.0 / 480.0;
const 振る許容差の比: [f32; 2] = [1.0, 2.0];

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 五つの軸_休ませてから傾けた一組を記録する() {
    println!("法線の逆向きの重力で{傾ける前に休ませる細分の本数}細分休ませた後に重力を鉛直へ戻す。細分0は戻した細分である");
    let 式 = 増幅器の式::正接と刻み幅から生成する(傾きの正接, 細分の刻み幅の秒);
    for 許容差の比 in 振る許容差の比 {
        let 場合 = 場合を組む(
            傾きの正接,
            0.0,
            許容差の比,
            段階A1の場面からの一つの変更::法線の逆向きの重力で休ませてから真の重力へ戻す,
        );
        let 記録 = super::一組を綴る(&場合);
        let 許容差 = 記録[1].接線の行の許容差;
        println!(
            "式の予測 許容差{許容差の比}倍 細分0の比={:.6}(実測{:.6}) 細分1の比={:.6}(実測{:.6}) 委譲の文の予測=増幅器は現れない",
            式.一本目の細分の比の予測(許容差, f64::from(許容差の比)),
            記録[0].最後の反復の後の円錐の比(),
            式.二本目の細分の比の予測(許容差, f64::from(許容差の比)),
            記録[1].最後の反復の後の円錐の比()
        );
    }
}
