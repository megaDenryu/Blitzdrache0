//! 記録しながら進める工程が本番の試験用の工程`一細分進める`と1ビットも違わないことの試験(Issue #59の第4段階)。
//! 同じ場面を2つ組み、片方を`一細分進める`で、片方を`記録しながら一細分進める`(入口の読み取りも含む)で64細分進め、
//! 配置・運動状態・直前の細分の観測が等しいことを固定する。この試験が通らない限り、計器の表の値は本番の値でない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」

#![cfg(test)]

use super::case::許容差依存の診断の場合;
use super::scene_variation::段階A1の場面からの一つの変更;
use super::並べる細分の本数;
use crate::contact::normal_tangential_system::接線の行への許容差の適用規則;

#[test]
fn 記録しながら進めた六十四細分は本番の細分と全桁一致する() {
    let 場合 = 許容差依存の診断の場合 {
        静止摩擦係数の値: 0.6,
        傾きの正接: 0.55,
        鉛直軸まわりの回しの度: 0.0,
        許容差の比: 1.0,
        行への適用規則: 接線の行への許容差の適用規則::許容差以下の接線変位の拘束行を追加しない, // 2026-09-12からの本番の形
        変更: 段階A1の場面からの一つの変更::無し,
    };
    let 条件 = 場合.坂の場面の条件を組む();
    let mut 本番 = 場合.場面を組む();
    let mut 記録つき = 場合.場面を組む();
    for 番号 in 0..並べる細分の本数 {
        本番.一細分進める();
        let 記録 = 記録つき.記録しながら一細分進める(番号, &条件, true);
        assert_eq!(本番.箱の配置, 記録つき.箱の配置, "細分{番号}で配置がずれた");
        assert_eq!(本番.箱の運動状態, 記録つき.箱の運動状態, "細分{番号}で運動状態がずれた");
        assert_eq!(本番.直前の細分の観測, 記録つき.直前の細分の観測, "細分{番号}で観測がずれた");
        assert_eq!(記録.反復ごと.len(), 2, "位置の反復回数は2である");
    }
    assert_eq!(
        本番.粘着の候補が解けなかった接触点集合の延べ数,
        記録つき.粘着の候補が解けなかった接触点集合の延べ数
    );
    assert_eq!(本番.錨を置き直した細分の延べ数, 記録つき.錨を置き直した細分の延べ数);
}
