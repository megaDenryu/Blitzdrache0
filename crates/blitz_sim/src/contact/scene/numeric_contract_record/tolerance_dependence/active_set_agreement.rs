//! 同じ配置へ2つの行への適用規則を当てて、有効集合の探索が勝たせた集合が一致するかを読む工程(Issue #59の第4段階の
//! 段階A3)。段階A3の候補(i')は接線の行を1本落とすため、連立の階数が下がって探索が別の集合を選びうる。その細分を
//! 数えるための読み取りである。
//! 入口の読み取り(`entry_reading`)から分けているのは、あちらが倍精度の参照を3回解く重い読み取りであり、細分ごとに
//! 読むかどうかを計器が選ぶのに対し、こちらが単精度の探索を2回するだけで細分ごとに常に読めるためである。
//! 2つの軌道を並べるのではなく同じ配置へ2つの適用規則を当てるのは、軌道の差を採否の差へ混ぜないためである
//! (段階A1の計測点1が倍率1倍と2倍でやっている形と同じである)。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::normal_tangential_system::接線の行への許容差の適用規則;
use crate::contact::scene::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_body::配置;
use crate::rigid_xpbd::姿勢自由度の参加者;

impl 一つの箱と静的な直方体の場面 {
    /// この配置で、場面の適用規則と設計候補(i)(右辺の δ を零にする)の勝った有効集合が違うか。
    /// どちらかで有効集合が定まらなければ比べられないため無しである。場面の適用規則が候補(i)そのものなら常に偽である。
    pub(super) fn 候補一と勝った有効集合が違うか(
        &self, 接触点集合: &[剛体と静的世界の接触拘束], 配置: &配置
    ) -> Option<bool> {
        let 場面の綴り = self.勝った有効集合の綴り(接触点集合, 配置, self.試験の許容差の適用規則.行への適用規則())?;
        let 候補一の綴り =
            self.勝った有効集合の綴り(接触点集合, 配置, 接線の行への許容差の適用規則::全部の拘束行を追加し右辺から許容差を外す)?;
        Some(場面の綴り != 候補一の綴り)
    }

    // 指定の行への適用規則で連立を組み直し、探索が勝たせた有効集合の綴り。定まらなければ無しである。
    fn 勝った有効集合の綴り(
        &self,
        接触点集合: &[剛体と静的世界の接触拘束],
        配置: &配置,
        行への適用規則: 接線の行への許容差の適用規則,
    ) -> Option<String> {
        let 参加者 = 姿勢自由度の参加者::動的(*配置, &self.箱の質量特性);
        let 適用規則 = self.試験の許容差の適用規則.行への適用規則を差し替える(行への適用規則);
        let (連立, _) = self.法線と接線の連立を許容差の適用規則で組む(接触点集合, &参加者, 適用規則);
        連立.定まった解の内訳を読む().map(|内訳| 内訳.有効集合の綴り())
    }
}
