//! 細分の第一反復で、解法が求めた位置の補正と、配置に実際に入った補正の差を追う工程(Issue #103の段階A5の計測8)。
//! 段階A5の計測2は、どの姿勢でも接線の行が全部積まれ、入口の接線変位も元の行空間の残差も姿勢で10倍違わないことを
//! 測った。にもかかわらず細分の終わりの接線変位だけが回し0度と回し45度で12倍違う。差は連立方程式を解いた後に生まれる。
//! そこで、(1)解法が求めた補正が接触点へ与える接線の変位、(2)その補正を配置へ当てた直後の接線変位、
//! (3)解法が求めた並進と、二段の位置へ実際に入った並進の差、の3つを読む。
//! (3)が零でなければ、補正が位置の表現で落ちている(Issue #59の第2段階の重心の位置の量子化と同じ機構が、
//! 二段の位置を入れた後も残っていることになる)。零なら、差は細分の残りの積分で生まれている。
//! 解を取り出すのは本番と同じ口(`相補条件を満たす有効集合で同時に解く`と`第1の参加者への補正の合計`)だけであり、
//! 受理の判定も円錐の判定も書き写さない。したがってこの読み取りは、受理を通った細分でだけ本番の補正と一致する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 1つの接触点集合の非貫通は同時に解く」

#![cfg(test)]

use blitz_math::{ワールド, 変位};

use super::anchor_displacement::錨からの接線変位の長さの並び;
use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::normal_tangential_system::相補条件を満たす有効集合を探した結末;
use crate::contact::scene::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_body::配置;
use crate::rigid_xpbd::{予測の状態, 姿勢自由度の参加者};

/// 第一反復の補正の追跡。解が定まらなかった細分では無しである。
pub(super) struct 第一反復の補正の追跡 {
    解法が求めた並進: 変位<ワールド>,
    配置へ実際に入った並進: 変位<ワールド>,
    補正の前の接線変位: Vec<f64>,
    補正の後の接線変位: Vec<f64>,
    補正の前の重心の綴り: String,
    補正の後の重心の綴り: String,
}

impl 第一反復の補正の追跡 {
    /// 解法が求めた並進と、二段の位置へ実際に入った並進の差の長さ。零でなければ補正が位置の表現で落ちている。
    pub(super) fn 落ちた並進の長さ(&self) -> f32 {
        (self.配置へ実際に入った並進 - self.解法が求めた並進).長さ().値()
    }

    /// 表へ綴る形。
    pub(super) fn 綴り(&self) -> String {
        format!(
            "解法が求めた並進の長さ={:.4e} 配置へ入った並進の長さ={:.4e} 落ちた長さ={:.4e} 補正前の接線変位={:?} 補正後の接線変位={:?} 補正前の重心={} 補正後の重心={}",
            self.解法が求めた並進.長さ().値(),
            self.配置へ実際に入った並進.長さ().値(),
            self.落ちた並進の長さ(),
            self.綴りへ畳む(&self.補正の前の接線変位),
            self.綴りへ畳む(&self.補正の後の接線変位),
            self.補正の前の重心の綴り,
            self.補正の後の重心の綴り
        )
    }

    fn 綴りへ畳む(&self, 並び: &[f64]) -> Vec<String> {
        並び.iter().map(|値| format!("{値:.4e}")).collect()
    }
}

impl 一つの箱と静的な直方体の場面 {
    /// 第一反復の入口の配置から、解法が求めた補正を読み、その補正を当てた配置と比べる。状態は書き換えない。
    pub(super) fn 第一反復の補正を追う(
        &self,
        接触点集合: &[剛体と静的世界の接触拘束],
        予測: &予測の状態,
    ) -> Option<第一反復の補正の追跡> {
        let 参加者 = 姿勢自由度の参加者::動的(*予測.配置(), &self.箱の質量特性);
        let (連立, _) = self.法線と接線の連立を組む(接触点集合, &参加者);
        let 相補条件を満たす有効集合を探した結末::有効集合が定まった { 同時解, .. } = 連立.相補条件を満たす有効集合で同時に解く()
        else {
            return None;
        };
        let 補正 = 連立.第1の参加者への補正の合計(&同時解);
        let 補正の後 = 予測.補正を適用する(&補正);
        Some(第一反復の補正の追跡 {
            解法が求めた並進: 補正.並進(),
            配置へ実際に入った並進: 補正の後.配置().重心の位置() - 予測.配置().重心の位置(),
            補正の前の接線変位: 錨からの接線変位の長さの並び(接触点集合, 予測.配置()),
            補正の後の接線変位: 錨からの接線変位の長さの並び(接触点集合, 補正の後.配置()),
            補正の前の重心の綴り: 重心の綴り(予測.配置()),
            補正の後の重心の綴り: 重心の綴り(補正の後.配置()),
        })
    }
}

// 二段の位置の粗い側と細かい側を1行へ綴る。細かい側が補正を受け取ったかを読むためにある。
fn 重心の綴り(配置: &配置) -> String {
    format!("{:?}", 配置.重心の位置())
}
