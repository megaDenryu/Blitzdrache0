//! 坂の箱がその刻み数のあいだ保持したか滑走したかの分類(Issue #59の数値契約の診断)。
//! 判定は2つの事実で決まる。坂に沿った変位が保持の上限(1ミリメートル)の内側であることと、最後の細分で
//! 滑走中と印された接触点が無いことである。2つを両方見るのは、円錐を超えた直後の細分ではまだ変位が小さく、
//! 変位だけでは滑走へ移った事実を見落とすためである。
//! 変位を一緒に持つのは、表が分類だけでなく変位の桁も見せるからである。分類が同じでも桁が3桁違えば、
//! 2つの場合が同じ状態にあるとは限らない。
//! 粘着の候補が解けなかった細分の延べ数と、錨を置き直した細分の延べ数も一緒に持つ。滑走した組でこの2つが
//! 大きく保持した組で小さければ、滑る原因が「混合連立が相補条件を満たす有効集合を見つけられず法線だけの連立へ
//! 落ちて静止摩擦が丸ごと消えること」であると言える。分類だけでは、滑った理由が円錐の超過なのか解の不在なのかを
//! 分けられない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

// 受入条件が定める保持の上限。`slope_tests`が固定する値と同じである。
const 保持と見なす変位の上限: f32 = 1.0e-3;

/// 坂の箱の保持と滑走の分類。
pub(super) struct 保持と滑走の分類 {
    坂に沿った変位: f32,
    滑走中の接触点の数: usize,
    粘着の候補が解けなかった延べ数: usize,
    錨を置き直した細分の延べ数: usize,
}

impl 保持と滑走の分類 {
    pub(super) fn 場面の走行の結果から決める(
        坂に沿った変位: f32,
        滑走中の接触点の数: usize,
        粘着の候補が解けなかった延べ数: usize,
        錨を置き直した細分の延べ数: usize,
    ) -> Self {
        Self {
            坂に沿った変位,
            滑走中の接触点の数,
            粘着の候補が解けなかった延べ数,
            錨を置き直した細分の延べ数,
        }
    }

    /// 混合連立が相補条件を満たす有効集合を見つけられず法線だけの連立へ落ちた、接触点集合の延べ数。
    pub(super) fn 粘着の候補が解けなかった延べ数(&self) -> usize {
        self.粘着の候補が解けなかった延べ数
    }

    /// 錨を置き直した細分の延べ数。接触の開始と、円錐を超えて滑走中と印された細分で立つ。
    pub(super) fn 錨を置き直した細分の延べ数(&self) -> usize {
        self.錨を置き直した細分の延べ数
    }

    pub(super) fn 坂に沿った変位(&self) -> f32 {
        self.坂に沿った変位
    }

    /// 保持しているか。変位が上限の内側で、かつ最後の細分に滑走中の接触点が無いときだけ真である。
    pub(super) fn 保持しているか(&self) -> bool {
        self.坂に沿った変位.abs() <= 保持と見なす変位の上限 && self.滑走中の接触点の数 == 0
    }

    /// 表へ書く分類の綴り。
    pub(super) fn 綴り(&self) -> &'static str {
        if self.保持しているか() { "保持" } else { "滑走" }
    }
}
