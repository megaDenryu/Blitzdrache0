//! 細分ごとの円錐の比と、位置から再構成された下り向きの速さの並び(Issue #59の原因の環の特定)。
//! 平衡では比が傾きの正接に等しく、速さが零であるはずである。実際には両方が細分ごとに振れ、速さは符号を
//! 交互に変える。振れ幅が円錐の半径と平衡の比の隔たりを超えると、保持していた組が1本の細分で滑走へ落ちる。
//! この型が振れ幅と符号の反転の回数を持つのは、保持する組と滑走する組でこの2つが違うことを示せば、原因の環が
//! 「解法上の残差が速度の再構成を介して次の細分の予測へ入り、細分ごとの振動を作ること」だと言えるためである。
//! 集めるのに細分ごとに場面を組み直すのは、第一反復の入口の値を読む口が場面を進めないためである。本数の2乗に
//! 比例する費用が掛かるが、見る本数が64本であるため許す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::diagnostic_case::数値契約の診断の一つの場合;

/// 細分ごとの比と速さの並び。
pub(super) struct 細分ごとの比と速さの並び {
    比の並び: Vec<f64>,
    下り向きの速さの並び: Vec<f32>,
}

impl 数値契約の診断の一つの場合 {
    /// 細分0から指定の本数まで、第一反復の入口の比と、その細分の終わりの下り向きの速さを集める。
    pub(super) fn 細分ごとの比と速さを集める(&self, 本数: usize) -> 細分ごとの比と速さの並び {
        let mut 比の並び = Vec::new();
        let mut 下り向きの速さの並び = Vec::new();
        for 番号 in 0..本数 {
            let 比 = self
                .指定の細分の第一反復を二つの精度で読む(番号)
                .map_or(0.0, |読み取り| 読み取り.単精度.合力と法線の合計の比());
            比の並び.push(比);
            下り向きの速さの並び.push(self.指定の細分までの下り向きの速さ(番号));
        }
        細分ごとの比と速さの並び {
            比の並び,
            下り向きの速さの並び,
        }
    }
}

impl 細分ごとの比と速さの並び {
    /// 細分0を除いた比の振れ幅(最大と最小の差)。円錐の半径と平衡の比の隔たりと比べる量である。
    /// 細分0を除くのは、そこが初めの食い込みを解く過渡であり、法線の乗数が平衡の3.7倍あって比が桁で小さく出る
    /// ためである。入れると振れ幅が過渡の1点で決まり、以後の周期の大きさが読めない。
    pub(super) fn 初めの細分を除いた比の振れ幅(&self) -> f64 {
        let 以後 = self.比の並び.get(1..).unwrap_or_default();
        以後.iter().copied().fold(f64::MIN, f64::max) - 以後.iter().copied().fold(f64::MAX, f64::min)
    }

    /// 細分0を除いた比の最大。円錐の半径0.6までの余裕を読む値である。
    pub(super) fn 初めの細分を除いた比の最大(&self) -> f64 {
        self.比の並び.get(1..).unwrap_or_default().iter().copied().fold(f64::MIN, f64::max)
    }

    /// 下り向きの速さが符号を変えた回数。振動の有無を1つの数で表す。
    pub(super) fn 速さの符号が反転した回数(&self) -> usize {
        self.下り向きの速さの並び.windows(2).filter(|組| 組[0] * 組[1] < 0.0).count()
    }

    /// 下り向きの速さの絶対値の最大。残差が速度へどれだけ移ったかの大きさである。
    pub(super) fn 速さの絶対値の最大(&self) -> f32 {
        self.下り向きの速さの並び.iter().map(|速さ| 速さ.abs()).fold(0.0, f32::max)
    }

    /// 細分ごとの1行を綴る。
    pub(super) fn 綴る(&self, 見出し: &str) {
        println!(
            "[{見出し}] 本数={} 細分0を除く比の振れ幅={:.6} 比の最大={:.6} 速さの符号の反転={}回 速さの絶対値の最大={:.6e}",
            self.比の並び.len(),
            self.初めの細分を除いた比の振れ幅(),
            self.初めの細分を除いた比の最大(),
            self.速さの符号が反転した回数(),
            self.速さの絶対値の最大(),
        );
        for (番号, (比, 速さ)) in self.比の並び.iter().zip(self.下り向きの速さの並び.iter()).enumerate() {
            println!("  細分{番号} 比={比:.6} 下り向きの速さ={速さ:.6e}");
        }
    }
}
