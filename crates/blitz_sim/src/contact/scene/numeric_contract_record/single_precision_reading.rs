//! 単精度の本番の経路で粘着の候補を1回解き、比べる量を読み取る工程(Issue #59の数値契約の診断)。
//! 読む口は本番の細分の工程が読むものと同じ3つである(連立を組む・相補条件を満たす有効集合で解く・仮の乗数の
//! 集まりを求める)。工程を場面のメソッドにしているのは、連立を組む口と仮の乗数を求める口を場面が持つためである。
//! 倍精度の側(`double_precision_reading`)と分けているのは、読む経路が別だからである。読み取った後の形は同じ型である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::super::super::normal_tangential_system::相補条件を満たす有効集合を探した結末;
use super::super::super::static_friction::接線のラグランジュ乗数;
use super::super::substep_harness::一つの箱と静的な直方体の場面;
use super::candidate_reading::粘着の候補の読み取り;
use crate::rigid_xpbd::姿勢自由度の参加者;
use crate::xpbd::ラグランジュ乗数;

impl 一つの箱と静的な直方体の場面 {
    /// 単精度の本番の経路で接触点集合1つの粘着の候補を解き、比べる量を読み取る。状態は書き換えない。
    pub(super) fn 単精度で粘着の候補を読む(
        &self,
        接触点集合: &[剛体と静的世界の接触拘束],
        参加者: &姿勢自由度の参加者,
    ) -> 粘着の候補の読み取り {
        let (連立, 点を入れた結果) = self.法線と接線の連立を組む(接触点集合, 参加者);
        let 点ごとの法線の拘束違反 = (0..連立.点の数())
            .map(|番号| f64::from(連立.法線の一行を読む(番号).map_or(0.0, |一行| 一行.隔たり().値())))
            .collect();
        let 点ごとの接線変位 = (0..連立.点の数())
            .map(|番号| f64::from(連立.接線の一行を読む(番号).map_or(0.0, |一行| 一行.接線変位の長さ().値())))
            .collect();
        let 同時解 = match 連立.相補条件を満たす有効集合で同時に解く() {
            相補条件を満たす有効集合を探した結末::有効集合が定まった(同時解) => 同時解,
            相補条件を満たす有効集合を探した結末::相補条件を満たす有効集合が無い => {
                return 粘着の候補の読み取り::解けなかった結末から組む("相補条件を満たす有効集合が無い");
            }
            相補条件を満たす有効集合を探した結末::表現の精度が不足した => {
                return 粘着の候補の読み取り::解けなかった結末から組む("表現の精度が不足した");
            }
        };
        let 仮の乗数 = self.仮の乗数の集まりを求める(接触点集合, &連立, &同時解, &点を入れた結果);
        let mut 法線の乗数の合計 = ラグランジュ乗数::零();
        let mut 接線の合力 = 接線のラグランジュ乗数::零();
        for (番号, 拘束) in 接触点集合.iter().enumerate() {
            法線の乗数の合計 = 法線の乗数の合計 + 拘束.法線のラグランジュ乗数() + 同時解.一点の法線の乗数の増分(番号);
            接線の合力 = 接線の合力 + 仮の乗数.一点の仮の接線の乗数(番号).確定する接線の乗数();
        }
        let 円錐の内側か = 接触点集合.first().is_some_and(|拘束| 仮の乗数.円錐の内側か(拘束.引数().接触物性));
        粘着の候補の読み取り::六つの量から組む(
            "定まった",
            点ごとの法線の拘束違反,
            点ごとの接線変位,
            f64::from(法線の乗数の合計.値()),
            f64::from(接線の合力.大きさ().値()),
            円錐の内側か,
        )
    }
}
