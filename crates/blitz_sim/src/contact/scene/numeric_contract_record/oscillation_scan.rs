//! 細分ごとの振動を測る計器(Issue #59の原因の環の特定)。
//! 4つの組を見る。正接0.50の許容差1倍(保持)と0.5倍(滑走)、正接0.55の回し30度(保持)と回し0度(滑走)である。
//! どの対も1つの条件だけが違って分類が違う。細分0から64本まで、第一反復の入口の円錐の比と、その細分の終わりに
//! 位置から再構成された下り向きの速さを並べ、比の振れ幅と速さの符号の反転の回数を出す。
//! 平衡では比が傾きの正接に等しく速さが零であるはずである。保持する組と滑走する組で振れ幅が違えば、原因の環は
//! 「解法上の残差が速度の再構成を介して次の細分の予測へ入り、細分ごとの振動を作ること」である。
//! 正接0.55では平衡の比0.55と円錐の半径0.6の隔たりが0.05しか無く、振れ幅がこれを超えると1本の細分で滑走へ落ちる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_math::ラジアン;

use super::diagnostic_case::数値契約の診断の一つの場合;

// 並べる細分の本数。8細分が基本刻み1本であり、64本は8刻みに当たる。
const 並べる細分の本数: usize = 64;

fn 回しのラジアン(回しの度: f32) -> f32 {
    ラジアン::度から(回しの度).値()
}

// 見る4つの組。名前と場合の対である。
fn 見る組の並び() -> Vec<(&'static str, 数値契約の診断の一つの場合)> {
    vec![
        (
            "正接0.50_許容差1倍_保持",
            数値契約の診断の一つの場合::許容差の倍率から生成する(0.0, 0.50, 1.0),
        ),
        (
            "正接0.50_許容差0.5倍_滑走",
            数値契約の診断の一つの場合::許容差の倍率から生成する(0.0, 0.50, 0.5),
        ),
        (
            "正接0.55_回し30度_保持",
            数値契約の診断の一つの場合::回しと正接から生成する(回しのラジアン(30.0), 0.55),
        ),
        ("正接0.55_回し0度_滑走", 数値契約の診断の一つの場合::回しと正接から生成する(0.0, 0.55)),
    ]
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 細分ごとの円錐の比と再構成された速さの振れを記録する() {
    println!("平衡では比が傾きの正接に等しく、下り向きの速さが零であるはずである。円錐の半径は静止摩擦係数0.6である");
    for (名前, 場合) in 見る組の並び() {
        場合.細分ごとの比と速さを集める(並べる細分の本数).綴る(名前);
    }
}
