//! 解法の許容差だけを振った表を作る計器(Issue #59の必須の診断行列その3)。
//! 世界座標も相対の配置も変えず、行の右辺を解けたと見なす許容差の倍率だけを0.5倍・1倍・2倍に振り、傾きの正接
//! 0.50・0.55・0.61の保持と滑走の分類が変わるかを綴る。
//! 既存の `tolerance_boundary_tests` と分けているのは、あちらが世界座標を動かして許容差を変える走査であり、
//! 座標そのものの表せる細かさも同時に変えるためである。2つの原因を分けて見るには、座標を固定して取り決めの幅
//! だけを振る走査が別に要る。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_math::ラジアン;

use super::diagnostic_case::数値契約の診断の一つの場合;

const 振る許容差の比: &[f32] = &[0.5, 1.0, 2.0];
const 振る傾きの正接: &[f32] = &[0.50, 0.55, 0.61];
const 振る鉛直軸まわりの回しの度: &[f32] = &[0.0, 30.0, 45.0];
const 見る刻み数: usize = 600;

// 度で並べた回しを、場面の条件が受けるラジアンの実数へ直す。
fn 回しのラジアン(回しの度: f32) -> f32 {
    ラジアン::度から(回しの度).値()
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 解法の許容差だけを振って保持と滑走の分類が変わるかを記録する() {
    println!("刻み数={見る刻み数} 世界座標は既定のまま");
    println!("許容差の倍率 | 回し | 正接0.50 | 正接0.55 | 正接0.61");
    for 許容差の比 in 振る許容差の比.iter().copied() {
        for 回しの度 in 振る鉛直軸まわりの回しの度.iter().copied() {
            let 欄: Vec<String> = 振る傾きの正接
                .iter()
                .map(|正接| {
                    let 分類 =
                        数値契約の診断の一つの場合::許容差の倍率から生成する(回しのラジアン(回しの度), *正接, 許容差の比)
                            .刻みを進めて分類する(見る刻み数);
                    format!(
                        "{} ({:.3e} 解けず{} 置き直し{})",
                        分類.綴り(),
                        分類.坂に沿った変位(),
                        分類.粘着の候補が解けなかった延べ数(),
                        分類.錨を置き直した細分の延べ数()
                    )
                })
                .collect();
            println!("{許容差の比} | {回しの度}度 | {}", 欄.join(" | "));
        }
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 解法の許容差だけを振って単精度と倍精度の差がどう変わるかを記録する() {
    for 許容差の比 in 振る許容差の比.iter().copied() {
        for 正接 in 振る傾きの正接.iter().copied() {
            let 場合 = 数値契約の診断の一つの場合::許容差の倍率から生成する(0.0, 正接, 許容差の比);
            let 見出し = format!("許容差{許容差の比}倍_正接{正接}_細分0");
            match 場合.指定の細分の第一反復を二つの精度で読む(0) {
                Some(読み取り) => {
                    読み取り.綴る(&見出し);
                    if 読み取り.円錐の判定が食い違ったか() {
                        println!("  [食い違い] この地点で2つの経路の結末か円錐の判定が違う");
                    }
                }
                None => println!("[{見出し}] 接触点集合が無い"),
            }
        }
    }
}
