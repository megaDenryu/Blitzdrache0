//! 世界内の平行移動の表を作る計器(Issue #59の必須の診断行列その2)。
//! 同じ相対配置のまま、坂と箱をまとめて坂の面の法線の向きへ動かした4つの置き方について、傾きの正接3つの保持と
//! 滑走の分類を綴る。4つは、原点付近・いまの約20.5メートル・表現の刻みが2倍になる移動・その10倍である。
//! 法線と直交する軸への移動は、坂の面の法線の向きへ動かす口しか場面が持たないため、坂の姿勢の回しで代える。
//! 回し45度の場面では坂の面の法線が世界の3軸すべてに成分を持ち、法線の向きへ動かすと接触に無関係な軸の座標も
//! 同じ桁で大きくなる。したがって回しを振ることが、直交する軸への移動を含んだ走査になる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use blitz_math::メートル;

use super::diagnostic_case::数値契約の診断の一つの場合;

// 坂の面の法線の向きへ動かす長さのメートル。0は場面の既定(接触点が原点から約20.5メートル)である。
// 20.4999は坂の中心から接触点までの長さであり、これだけ動かすと接触点の座標が2倍になって表現の刻みも2倍になる。
const 動かす長さのメートル: &[f32] = &[-20.4999, 0.0, 20.4999, 204.999];
const 振る傾きの正接: &[f32] = &[0.50, 0.55, 0.61];
const 振る鉛直軸まわりの回しの度: &[f32] = &[0.0, 30.0, 45.0];
const 見る刻み数: usize = 600;
// 2つの精度を並べる細分の番号。1本目の過渡がこの表でも判定を決めているかを見る。
const 二つの精度を並べる細分の番号: usize = 0;

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 世界内の平行移動で保持と滑走の分類が変わるかを記録する() {
    println!("刻み数={見る刻み数}");
    println!("動かす長さ | 回し | 正接0.50 | 正接0.55 | 正接0.61");
    for 動かす長さ in 動かす長さのメートル.iter().copied().map(メートル::生成する) {
        for 回しの度 in 振る鉛直軸まわりの回しの度.iter().copied() {
            let 欄: Vec<String> = 振る傾きの正接
                .iter()
                .map(|正接| {
                    let 分類 = 数値契約の診断の一つの場合::回しの度と法線の向きへ動かす長さから生成する(
                        回しの度,
                        *正接,
                        動かす長さ,
                    )
                    .刻みを進めて分類する(見る刻み数);
                    format!(
                        "{} ({:.3e} 解けず{} 置き直し{})",
                        分類.綴り(),
                        分類.坂に沿った変位(),
                        分類.粘着の候補が解けなかった延べ数(),
                        分類.錨を置き直した細分の延べ数()
                    )
                })
                .collect();
            println!("{} | {回しの度}度 | {}", 動かす長さ.値(), 欄.join(" | "));
        }
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 世界内の平行移動で単精度と倍精度の差がどう変わるかを記録する() {
    for 動かす長さ in 動かす長さのメートル.iter().copied().map(メートル::生成する) {
        for 正接 in 振る傾きの正接.iter().copied() {
            let 場合 =
                数値契約の診断の一つの場合::回しの度と法線の向きへ動かす長さから生成する(0.0, 正接, 動かす長さ);
            let 見出し = format!("移動{}_正接{正接}_細分{二つの精度を並べる細分の番号}", 動かす長さ.値());
            場合.一つの細分の二つの精度を綴る(&見出し, 二つの精度を並べる細分の番号);
        }
    }
}
