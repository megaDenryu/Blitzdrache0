//! 坂の境界の表を作る計器(Issue #59の必須の診断行列その1)。
//! 静止摩擦係数0.6に対して傾きの正接を5つ、鉛直軸まわりの回しを3つ振り、600刻みの坂に沿った変位と保持と滑走の
//! 分類を綴る。正接0.40だけは3600刻みも綴る。600刻みでは保持に見える傾きが後の細分で円錐を超えることがあるためである。
//! 併せて、同じ15の組について細分1本目と2本目の第一反復を単精度と倍精度で並べる。1本目を見るのは、正接0.55が
//! 滑るのが初めの食い込みを解く過渡だと2026-09-03の記録が特定しているためである。
//! 分類の表は最適化を有効にした構成で走らせる(デバッグ構成では1つの組に分の単位で掛かる)。構成で分類が
//! 変わらないことを「はず」で済ませないため、1組だけを両方の構成で走らせて突き合わせる計器を別に置く。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::diagnostic_case::{数値契約の診断の一つの場合, 静止摩擦係数の値};

// Issue #59が名指しした傾きの正接。0.55は静止摩擦係数0.6の十分内側であり、0.61は十分外側である。
const 振る傾きの正接: [f32; 5] = [0.40, 0.50, 0.55, 0.59, 0.61];
// 鉛直軸まわりの回しの度。接線の軸の取り方が挙動へ漏れていれば、この3つで保持と滑走の判定が変わる。
const 振る鉛直軸まわりの回しの度: &[f32] = &[0.0, 30.0, 45.0];
const 短く見る刻み数: usize = 600;
const 長く見る刻み数: usize = 3600;
// 長く見る傾き。600刻みでは保持に見えても後の細分で円錐を超えることがあるため、3600刻みでも見る。
const 長く見る傾きの正接: f32 = 0.40;
// 2つの精度を並べる細分の番号。1本目は初めの食い込みを解く過渡であり、2本目はその次である。
const 二つの精度を並べる細分の番号: [usize; 2] = [0, 1];
// 構成を突き合わせる1組。Issue #59が名指しした正接のうち、いま判定が回しで割れているものを選ぶ。
const 構成を突き合わせる傾きの正接: f32 = 0.55;
const 構成を突き合わせる回しの度: f32 = 0.0;

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 坂の境界の保持と滑走の表を記録する() {
    println!("静止摩擦係数={静止摩擦係数の値} 刻み数={短く見る刻み数}");
    println!("傾きの正接 | 0度の変位 | 0度 | 30度の変位 | 30度 | 45度の変位 | 45度");
    for 正接 in 振る傾きの正接 {
        let 欄: Vec<String> = 振る鉛直軸まわりの回しの度
            .iter()
            .map(|回しの度| {
                let 分類 = 数値契約の診断の一つの場合::回しの度と正接から生成する(*回しの度, 正接).刻みを進めて分類する(短く見る刻み数);
                format!(
                    "{:.3e} | {} | 解けず{} 置き直し{}",
                    分類.坂に沿った変位(),
                    分類.綴り(),
                    分類.粘着の候補が解けなかった延べ数(),
                    分類.錨を置き直した細分の延べ数()
                )
            })
            .collect();
        println!("{正接} | {}", 欄.join(" | "));
    }
    println!("刻み数={長く見る刻み数} 傾きの正接={長く見る傾きの正接}");
    for 回しの度 in 振る鉛直軸まわりの回しの度.iter().copied() {
        let 分類 =
            数値契約の診断の一つの場合::回しの度と正接から生成する(回しの度, 長く見る傾きの正接).刻みを進めて分類する(長く見る刻み数);
        println!(
            "{回しの度}度 | {:.3e} | {} | 解けず{} 置き直し{}",
            分類.坂に沿った変位(),
            分類.綴り(),
            分類.粘着の候補が解けなかった延べ数(),
            分類.錨を置き直した細分の延べ数()
        );
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 坂の境界の単精度と倍精度の差を記録する() {
    for 正接 in 振る傾きの正接 {
        for 回しの度 in 振る鉛直軸まわりの回しの度.iter().copied() {
            let 場合 = 数値契約の診断の一つの場合::回しの度と正接から生成する(回しの度, 正接);
            for 番号 in 二つの精度を並べる細分の番号 {
                let 見出し = format!("正接{正接}_回し{回しの度}度_細分{番号}");
                場合.一つの細分の二つの精度を綴る(&見出し, 番号);
            }
        }
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 構成を突き合わせる一組の変位と分類を記録する() {
    let 分類 = 数値契約の診断の一つの場合::回しと正接から生成する(
        回しのラジアン(構成を突き合わせる回しの度),
        構成を突き合わせる傾きの正接,
    )
    .刻みを進めて分類する(短く見る刻み数);
    println!(
        "正接{構成を突き合わせる傾きの正接}_回し{構成を突き合わせる回しの度}度 | {:.9e} | {}",
        分類.坂に沿った変位(),
        分類.綴り()
    );
}
