//! 倍精度の参照計算が定めた解の、数値解法の内側の内訳を綴る工程(Issue #59が必須の診断行列に挙げた
//! 「擬似逆が捨てた固有の向きと理由」と「行ごとの残差」)。
//! 2つの精度を並べる綴り(`comparison_line`)から分けているのは、あちらが2つの経路の同じ量を並べるのに対し、
//! こちらが倍精度の側だけが持つ量を綴るからである。単精度の側の同じ量は本番の抜き出しの中に閉じており、
//! 場面からは読めない。単精度の側は既存の計器(`cone_breach_record` の円錐を超える細分の内訳)が別に綴る。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::super::super::normal_tangential_system::倍精度の解の内訳;
use crate::contact::symmetric_system::擬似逆が固有の向きを捨てた理由;

impl 倍精度の解の内訳 {
    /// 行ごとの残差と、捨てた固有の向きの数と理由を綴る。
    pub(super) fn 綴る(&self) {
        println!(
            "  倍精度の内訳 有効集合のビット並び={:#010b} 行数={} 残差のノルム={:.3e} 行ごとの残差の最大={:.3e}",
            self.有効集合のビット並び,
            self.行ごとの残差.len(),
            self.残差のノルム,
            self.行ごとの残差の最大(),
        );
        println!(
            "  倍精度の捨てた向き 偽の固有値={}本 右辺が許容差の内側={}本 捨てていない={}本",
            self.捨てた向きの数(擬似逆が固有の向きを捨てた理由::偽の固有値),
            self.捨てた向きの数(擬似逆が固有の向きを捨てた理由::右辺が許容差の内側),
            self.捨てた向きの数(擬似逆が固有の向きを捨てた理由::捨てていない),
        );
        for (k, 向き) in self.固有の向きごと.iter().enumerate() {
            println!(
                "  倍精度の向き{k} λ={:.6e} vᵀb={:.6e} δ={:.6e} {:?} | 行{k}の残差={:.3e} 許容差={:.3e}",
                向き.固有値,
                向き.右辺の射影,
                向き.許容差の射影,
                向き.捨てた理由,
                self.行ごとの残差.get(k).copied().unwrap_or(0.0),
                self.行ごとの解けたと見なす許容差.get(k).copied().unwrap_or(0.0),
            );
        }
    }

    /// 行ごとの残差の絶対値の最大。表の要約が読む。
    pub(super) fn 行ごとの残差の最大(&self) -> f64 {
        self.行ごとの残差.iter().map(|残差| 残差.abs()).fold(0.0, f64::max)
    }

    /// 指定の理由で扱われた固有の向きの数。
    pub(super) fn 捨てた向きの数(&self, 理由: 擬似逆が固有の向きを捨てた理由) -> usize {
        self.固有の向きごと.iter().filter(|向き| 向き.捨てた理由 == 理由).count()
    }
}
