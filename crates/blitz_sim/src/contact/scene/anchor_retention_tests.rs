//! 錨の保持の試験(判断16)。担当するのは、水平な床の上で箱を1メートル滑らせるあいだ、面と面の接触の4点が
//! 毎細分「継続」として対応付き、履歴が持つ錨が滑走の判定まで保たれることを固定することである。
//! 開始が1度でも起きれば、その細分で錨が新しく置き直されている(前の細分の記録を引き継げていない)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断16: 接触の履歴は参加者の組ごとに特徴の識別を鍵に全順序の併走で対応付け、暖機はしない」

#![allow(clippy::unwrap_used)]

use super::super::friction_coefficient::摩擦係数;
use super::slope_fixture::坂の場面を組む;
use super::slope_geometry::坂の場面の条件;
use super::static_friction_method::場面の静止摩擦の解き方;

const 滑らせる長さ: f32 = 1.0;
const 面と面の接触点の数: usize = 4;
const 見る細分数の上限: usize = 8000; // 秒速2メートルから μ_d = 0.05 で減速しても1メートル滑るのに十分な長さ

#[test]
fn 床の上で一メートル滑らせても接触の対応付けが継続のまま保たれる() {
    let 条件 = 坂の場面の条件 {
        傾きの正接: 0.0,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.05).unwrap(),
        下り向きの初速: 2.0,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    };
    let mut 場面 = 坂の場面を組む(&条件);
    let 初めの重心 = 場面.箱の配置.重心の位置();
    let mut 滑走を見た = false;
    let mut 進んだ長さ = 0.0;
    for 細分 in 0..見る細分数の上限 {
        場面.一細分進める();
        let 観測 = 場面.直前の細分の観測;
        assert_eq!(観測.接触点の数, 面と面の接触点の数, "細分{細分}で面と面の接触点が4つでない");
        if 細分 > 0 {
            assert_eq!(観測.開始した接触点の数, 0, "細分{細分}で接触が新規として始まり錨が置き直された");
        }
        滑走を見た |= 観測.滑走中の接触点の数 > 0;
        進んだ長さ = 場面.坂に沿った変位(初めの重心, &条件);
        if 進んだ長さ >= 滑らせる長さ {
            break;
        }
    }
    assert!(進んだ長さ >= 滑らせる長さ, "箱が1メートル滑っていない: {進んだ長さ}");
    assert!(滑走を見た, "滑走の判定が一度も起きていない");
}
