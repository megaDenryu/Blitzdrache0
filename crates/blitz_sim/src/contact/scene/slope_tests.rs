//! 坂の上の箱で判断13の静止摩擦と判断14の動摩擦の定量の基準を固定する試験。
//! 担当するのは5つである。傾きの正接が静止摩擦係数より小さい坂で箱が3600刻みで1ミリメートル以下しか動かないこと、
//! 大きい坂で滑り出すこと、鉛直軸まわりに場面ごと回しても滑り出す傾きの境界が変わらないこと(等方性)、
//! 滑走中の減速度が g(sinθ − μ_d cosθ) と相対誤差1パーセント以内で一致すること、
//! 静止摩擦の位置拘束を外した反証で坂の箱が下ることである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use std::f32::consts::PI;

use super::super::friction_coefficient::摩擦係数;
use super::slope_fixture::{一刻みの細分数, 坂の場面を組む};
use super::slope_geometry::{坂の場面の条件, 滑走の加速度};

const 静止する傾きの正接: f32 = 0.2;
const 滑る傾きの正接: f32 = 0.9;
const 静止摩擦係数の値: f32 = 0.6;
const 動摩擦係数の値: f32 = 0.2;
const 測り始めるまでの細分数: usize = 60; // 初めの食い込みの解消と接触の落ち着きに要る細分数
const 測る細分数: usize = 240;
const 測る秒数: f32 = 0.5; // 測る細分数 ÷ (1細分の刻み幅 1/480秒)
const 保持を見る刻み数: usize = 600;
const 滑走を見る刻み数: usize = 100;
const 滑走の加速度の許容: f32 = 0.01;
// 境界を挟む2つの傾き。実装が保持できる傾きの上限は静止摩擦係数0.6そのものでなく0.50から0.52の間にあり
// (正本の判断13の実装の細目に理由と実測を記した)、この2つはその境界を外から挟む。等方性の試験が見るのは
// 境界の値ではなく、3つの回しで保持と滑走の判定が同じになることである。
const 境界より緩い傾きの正接: f32 = 0.45;
const 境界より急な傾きの正接: f32 = 0.52;

fn 傾きの条件(傾きの正接: f32, 鉛直軸まわりの回し: f32, 下り向きの初速: f32) -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接,
        鉛直軸まわりの回し,
        静止摩擦係数: 摩擦係数::生成する(静止摩擦係数の値).unwrap(),
        動摩擦係数: 摩擦係数::生成する(動摩擦係数の値).unwrap(),
        下り向きの初速,
        静止摩擦の位置拘束を外すか: false,
    }
}

fn 刻みを進めて坂に沿った変位を測る(条件: &坂の場面の条件, 刻み数: usize) -> f32 {
    let mut 場面 = 坂の場面を組む(条件);
    let 初めの重心 = 場面.箱の配置.重心の位置();
    場面.細分を進める(刻み数 * 一刻みの細分数);
    場面.坂に沿った変位(初めの重心, 条件)
}

#[test]
fn 静止摩擦係数より緩い坂の箱は三千六百刻みで一ミリメートル以下しか動かない() {
    let 変位 = 刻みを進めて坂に沿った変位を測る(&傾きの条件(静止する傾きの正接, 0.0, 0.0), 3600);
    assert!(変位.abs() <= 1.0e-3, "坂に沿った変位が1ミリメートルを超えた: {変位}");
}

#[test]
fn 静止摩擦係数より急な坂の箱は滑り出す() {
    let 変位 = 刻みを進めて坂に沿った変位を測る(&傾きの条件(滑る傾きの正接, 0.0, 0.0), 滑走を見る刻み数);
    assert!(変位 > 0.1, "急な坂で箱が滑り出していない: {変位}");
}

#[test]
fn 鉛直軸まわりに回しても滑り出す傾きの境界が変わらない() {
    for 回し in [0.0, PI / 6.0, PI / 4.0] {
        let 緩い側 = 刻みを進めて坂に沿った変位を測る(&傾きの条件(境界より緩い傾きの正接, 回し, 0.0), 保持を見る刻み数);
        assert!(緩い側.abs() <= 1.0e-3, "回し{回し}で境界より緩い坂の箱が保持されなかった: {緩い側}");
        let 急な側 = 刻みを進めて坂に沿った変位を測る(&傾きの条件(境界より急な傾きの正接, 回し, 0.0), 保持を見る刻み数);
        assert!(急な側 > 1.0, "回し{回し}で境界より急な坂の箱が滑り出さなかった: {急な側}");
    }
}

#[test]
fn 滑走中の減速度は重力の斜面成分から動摩擦を引いた値と一致する() {
    let 条件 = 傾きの条件(滑る傾きの正接, 0.0, 1.0);
    let mut 場面 = 坂の場面を組む(&条件);
    場面.細分を進める(測り始めるまでの細分数);
    let 初めの速さ = 場面.下り向きの速さ(&条件);
    場面.細分を進める(測る細分数);
    let 測った加速度 = (場面.下り向きの速さ(&条件) - 初めの速さ) / 測る秒数;
    let 解析の加速度 = 滑走の加速度(滑る傾きの正接, 動摩擦係数の値);
    let 相対誤差 = (測った加速度 - 解析の加速度).abs() / 解析の加速度;
    assert!(
        相対誤差 <= 滑走の加速度の許容,
        "滑走の加速度が解析値と{滑走の加速度の許容}以上ずれた(測定{測った加速度}、解析{解析の加速度})"
    );
}

#[test]
fn 静止摩擦の位置拘束を外すと緩い坂の箱が下る() {
    let 条件 = 坂の場面の条件 {
        静止摩擦の位置拘束を外すか: true,
        ..傾きの条件(静止する傾きの正接, 0.0, 0.0)
    };
    let 変位 = 刻みを進めて坂に沿った変位を測る(&条件, 3600);
    assert!(変位 > 1.0e-3, "位置の静止摩擦を外しても箱が下らない: {変位}");
}
