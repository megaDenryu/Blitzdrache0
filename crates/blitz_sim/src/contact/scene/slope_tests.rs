//! 坂の上の箱で判断13の静止摩擦の定量の基準を固定する試験。
//! 担当するのは6つである。傾きの正接が静止摩擦係数より小さい坂で箱が3600刻みで1ミリメートル以下しか動かないこと、
//! 正接0.40でも3600刻みで1ミリメートル以下に留まること、大きい坂で滑り出すこと、鉛直軸まわりに場面ごと回しても
//! 正接0.50と0.55を600刻みで1ミリメートル以下に保持し正接0.61では滑走すること、静止摩擦の位置拘束を外した反証で
//! 坂の箱が下ること、接線を接触点ごとに順に射影する反証で正接0.50の坂の箱が保持の上限である1ミリメートルを超えて
//! 滑る一方、接触点集合の単位で同時に解けば同じ坂で1ミリメートル以下に留まることである。
//! 正接0.40を3600刻みで見るのは、600刻みでは保持に見える傾きが後の細分で円錐を超えることがあるためである
//! (改訂の前は回し0度の正接0.40が17878本目の細分で超えた)。反証が超えるべき長さを保持の上限と同じ1ミリメートルに置くのは、この反証が示すべきことが
//! 「同時に解かないと受入条件(a)の保持に不合格になる」ことだからである。
//! 滑走中の減速度は`sliding_deceleration_tests`が固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use std::f32::consts::PI;

use super::super::friction_coefficient::摩擦係数;
use super::residual_separation::場面の残差の分離;
use super::slope_fixture::{一刻みの細分数, 坂の場面を組む};
use super::slope_geometry::坂の場面の条件;
use super::static_friction_method::場面の静止摩擦の解き方;

const 静止する傾きの正接: f32 = 0.2;
const 滑る傾きの正接: f32 = 0.9;
const 静止摩擦係数の値: f32 = 0.6;
const 動摩擦係数の値: f32 = 0.2;
const 保持を見る刻み数: usize = 600;
const 滑走を見る刻み数: usize = 100;
// 受入条件が定める保持と滑走の傾き。静止摩擦係数0.6に対し、0.50と0.55は保持し0.61は滑走することを3方向で要求する。
const 三方向で保持を要求する傾きの正接: [f32; 2] = [0.50, 0.55];
const 保持を要求する傾きの正接: f32 = 0.50;
const 滑走を要求する傾きの正接: f32 = 0.61;
// 長く見て保持を要求する傾き。静止摩擦係数の3分の2であり、600刻みでは滑走の兆しが出ない傾きである。
const 長く見て保持を要求する傾きの正接: f32 = 0.40;
const 保持を要求する変位の上限: f32 = 1.0e-3;

fn 傾きの条件(傾きの正接: f32, 鉛直軸まわりの回し: f32, 下り向きの初速: f32) -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接,
        鉛直軸まわりの回し,
        静止摩擦係数: 摩擦係数::生成する(静止摩擦係数の値).unwrap(),
        動摩擦係数: 摩擦係数::生成する(動摩擦係数の値).unwrap(),
        下り向きの初速,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
        残差の分離: 場面の残差の分離::残差の変化を速度から除く,
    }
}

fn 刻みを進めて坂に沿った変位を測る(条件: &坂の場面の条件, 刻み数: usize) -> f32 {
    let mut 場面 = 坂の場面を組む(条件);
    let 初めの重心 = 場面.箱の配置.重心の位置();
    場面.細分を進める(刻み数 * 一刻みの細分数);
    場面.坂に沿った変位(初めの重心, 条件)
}

#[test]
fn 静止摩擦係数より緩い坂の箱は三千六百刻みで一ミリメートル以下しか動かない() {
    let 変位 = 刻みを進めて坂に沿った変位を測る(&傾きの条件(静止する傾きの正接, 0.0, 0.0), 3600);
    assert!(変位.abs() <= 1.0e-3, "坂に沿った変位が1ミリメートルを超えた: {変位}");
}

#[test]
fn 静止摩擦係数の三分の二の坂の箱は三千六百刻みで一ミリメートル以下しか動かない() {
    let 変位 = 刻みを進めて坂に沿った変位を測る(&傾きの条件(長く見て保持を要求する傾きの正接, 0.0, 0.0), 3600);
    assert!(
        変位.abs() <= 保持を要求する変位の上限,
        "正接{長く見て保持を要求する傾きの正接}の坂に沿った変位が1ミリメートルを超えた: {変位}"
    );
}

#[test]
fn 静止摩擦係数より急な坂の箱は滑り出す() {
    let 変位 = 刻みを進めて坂に沿った変位を測る(&傾きの条件(滑る傾きの正接, 0.0, 0.0), 滑走を見る刻み数);
    assert!(変位 > 0.1, "急な坂で箱が滑り出していない: {変位}");
}

#[test]
fn 鉛直軸まわりに回しても正接零点五零と零点五五を保持し正接零点六一で滑走する() {
    // 3つの回し。接線の軸の取り方が挙動へ漏れていれば、この回しで保持と滑走の判定が変わる。
    for 回し in [0.0, PI / 6.0, PI / 4.0] {
        for 正接 in 三方向で保持を要求する傾きの正接 {
            let 保持側 = 刻みを進めて坂に沿った変位を測る(&傾きの条件(正接, 回し, 0.0), 保持を見る刻み数);
            assert!(
                保持側.abs() <= 保持を要求する変位の上限,
                "回し{回し}で正接{正接}の坂の箱が保持されなかった: {保持側}"
            );
        }
        let 滑走側 = 刻みを進めて坂に沿った変位を測る(&傾きの条件(滑走を要求する傾きの正接, 回し, 0.0), 保持を見る刻み数);
        assert!(
            滑走側 > 1.0,
            "回し{回し}で正接{滑走を要求する傾きの正接}の坂の箱が滑り出さなかった: {滑走側}"
        );
    }
}

#[test]
fn 静止摩擦の位置拘束を外すと緩い坂の箱が下る() {
    let 条件 = 坂の場面の条件 {
        静止摩擦の解き方: 場面の静止摩擦の解き方::静止摩擦の位置拘束を外す,
        残差の分離: 場面の残差の分離::残差の変化を速度から除く,
        ..傾きの条件(静止する傾きの正接, 0.0, 0.0)
    };
    let 変位 = 刻みを進めて坂に沿った変位を測る(&条件, 3600);
    assert!(変位 > 1.0e-3, "位置の静止摩擦を外しても箱が下らない: {変位}");
}

#[test]
fn 接線を接触点ごとに順に射影すると正接零点五零の坂の箱が滑り出す() {
    let 同時に解く = 傾きの条件(保持を要求する傾きの正接, 0.0, 0.0);
    let 順に射影する = 坂の場面の条件 {
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点ごとに接線を順に射影する,
        残差の分離: 場面の残差の分離::残差の変化を速度から除く,
        ..傾きの条件(保持を要求する傾きの正接, 0.0, 0.0)
    };
    let 同時の変位 = 刻みを進めて坂に沿った変位を測る(&同時に解く, 保持を見る刻み数);
    let 順の変位 = 刻みを進めて坂に沿った変位を測る(&順に射影する, 保持を見る刻み数);
    assert!(
        同時の変位.abs() <= 保持を要求する変位の上限,
        "同時に解いても正接0.50の坂の箱が留まらない: {同時の変位}"
    );
    assert!(
        順の変位 > 保持を要求する変位の上限,
        "接線の同時解を外しても正接0.50の坂の箱が保持の上限に留まっている: {順の変位}"
    );
}
