//! 接線を接触点ごとに順に射影する反証の実装(判断13)。1点ずつ w̃_t で割った増分を求め、その補正を次の点の前に
//! 仮の配置へ適用する。同時解法(`substep_static_friction`)から分けているのは、こちらが本番の工程ではなく、
//! 同時解法を外すと定量の基準が落ちることを示すためだけに残す経路だからである。
//! この形では各点が物体全体の滑りを1点で戻そうとし、1点の補正が次の点の腕と有効逆質量を変える。接線の乗数が
//! 反復のたびに積み増され、傾きの正接0.50の坂で円錐を超えて集合が滑走へ落ちる(実測は
//! `_doc/計測/剛体の接触の摩擦と反発_2026-09-03.md`)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::super::static_friction::接触点の仮の接線の乗数;
use super::super::static_friction::接触点集合の仮の乗数の集まり;
use super::super::static_friction::静止摩擦の一回の仮の射影の結果;
use super::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_xpbd::{予測の状態, 姿勢自由度の参加者};

impl 一つの箱と静的な直方体の場面 {
    // 接触点集合1つの接線を順に射影する。円錐の内側なら仮の配置をそのまま返し、超えたら射影の前の配置へ戻す。
    pub(super) fn 接触点集合の静止摩擦を順に射影する(
        &self,
        接触点集合: &mut [剛体と静的世界の接触拘束],
        射影の前の予測: 予測の状態,
    ) -> 予測の状態 {
        let Some(先頭) = 接触点集合.first() else {
            return 射影の前の予測;
        };
        if 先頭.静止摩擦の解の状態().滑走中か() {
            return 射影の前の予測;
        }
        let 接触物性 = 先頭.引数().接触物性;
        let mut 仮の予測 = 射影の前の予測;
        let mut 仮の乗数 = 接触点集合の仮の乗数の集まり::空から始める();
        for (添字, 拘束) in 接触点集合.iter().enumerate() {
            let 参加者 = 姿勢自由度の参加者::動的(*仮の予測.配置(), &self.箱の質量特性);
            let 結果 = 拘束.静止摩擦を一回仮に射影する(&参加者);
            if let 静止摩擦の一回の仮の射影の結果::接線を戻す補正を求めた { 補正a, .. } = 結果 {
                仮の予測 = 仮の予測.補正を適用する(&補正a);
            }
            仮の乗数.一点を足す(
                添字,
                接触点の仮の接線の乗数::射影の結果と解の状態から決める(結果, 拘束.静止摩擦の解の状態()),
                拘束.法線のラグランジュ乗数(),
            );
        }
        if !仮の乗数.円錐の内側か(接触物性) {
            let 射影の前の参加者 = 姿勢自由度の参加者::動的(*射影の前の予測.配置(), &self.箱の質量特性);
            self.接触点集合を滑走中にする(接触点集合, &射影の前の参加者, &仮の乗数);
            return 射影の前の予測;
        }
        for (添字, 拘束) in 接触点集合.iter_mut().enumerate() {
            拘束.静止摩擦の仮の乗数を確定する(仮の乗数.一点の仮の接線の乗数(添字).確定する接線の乗数());
        }
        仮の予測
    }
}
