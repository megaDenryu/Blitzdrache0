//! 解けたと見なす許容差の大きさが、保持と滑走の境界を動かさないことの試験(判断13の2026-09-12の実装の細目の
//! 反証(4)(b))。担当するのは、坂と箱をまとめて坂の面の法線の向きへ動かし、許容差が2倍になる場面で保持できる傾きの
//! 上限が0.01以上動かないことを、受理の許容差の倍率0.5倍・1倍・2倍のそれぞれで固定することである。許容差は誤差の
//! 上限ではなく「ここまで残っていれば解けたものとして扱う」という取り決めであるため、取り決めの幅が物理の結果を
//! 変えない範囲を検査で固定する必要がある。
//! 振り方に法線の向きの平行移動を使うのは、許容差が接触点の世界座標の表現の刻みで決まるためである。坂の中心から
//! 接触点までの長さだけ動かすと座標が2倍になり、走査する傾きの範囲では全部の座標が次の2の冪の帯へ移って刻みが
//! ちょうど2倍になる。この振り方は座標そのものの表せる細かさも同時に粗くするため、許容差だけを単独で振る検査は
//! 受理の倍率を差し替える `slope_tolerance_scale_tests` が持つ。この試験は両方を重ねて振る。
//! 走査の上端を0.55にするのは、完了条件が正接0.55の保持を要求するためである。
//! 行ごとの許容差と残差の関係は`normal_tangential_system/tolerance_tests`が固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::super::friction_coefficient::摩擦係数;
use super::super::normal_tangential_system::{解けたと見なす許容差の倍率, 試験の許容差の当て方};
use super::slope_fixture::{一刻みの細分数, 坂の場面を移動と許容差の当て方で組む};
use super::slope_geometry::坂の場面の条件;
use super::slope_holding::坂の箱の保持と滑走;
use super::static_friction_method::場面の静止摩擦の解き方;

const 走査する傾きの正接: [f32; 6] = [0.50, 0.51, 0.52, 0.53, 0.54, 0.55];
const 保持を見る刻み数: usize = 600;
// 坂の中心から接触点までの長さ。これだけ法線の向きへ動かすと接触点の座標が2倍になり、表現の刻みが2倍になる。
const 許容差を二倍にする長さ: f32 = 20.4999;
// 境界が動いたと見なす差。走査の刻みと同じ大きさである。
const 境界が動いたと見なす差: f32 = 0.01;
const 振る受理の倍率: [f32; 3] = [0.5, 1.0, 2.0];

fn 走査する条件(傾きの正接: f32) -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    }
}

fn 保持しているか(傾きの正接: f32, 法線の向きへ動かす長さ: f32, 受理の倍率: f32) -> bool {
    let 条件 = 走査する条件(傾きの正接);
    let 当て方 =
        試験の許容差の当て方::本番と同じ当て方().受理の倍率を差し替える(解けたと見なす許容差の倍率::比から生成する(受理の倍率));
    let mut 場面 = 坂の場面を移動と許容差の当て方で組む(&条件, メートル::生成する(法線の向きへ動かす長さ), 当て方);
    let 初めの重心 = 場面.箱の配置.重心の位置();
    場面.細分を進める(保持を見る刻み数 * 一刻みの細分数);
    場面.保持と滑走を分類する(初めの重心, &条件) == 坂の箱の保持と滑走::保持
}

// 走査の下端から数えて連続して保持している最後の傾きの正接。下端で既に滑るなら無しである。
fn 保持できる傾きの上限(法線の向きへ動かす長さ: f32, 受理の倍率: f32) -> Option<f32> {
    let mut 上限 = None;
    for 正接 in 走査する傾きの正接 {
        if !保持しているか(正接, 法線の向きへ動かす長さ, 受理の倍率) {
            return 上限;
        }
        上限 = Some(正接);
    }
    上限
}

#[test]
fn 許容差が二倍になる場面でも保持できる傾きの上限が動かない() {
    for 受理の倍率 in 振る受理の倍率 {
        let もとの上限 = 保持できる傾きの上限(0.0, 受理の倍率).unwrap_or_else(|| {
            panic!("受理{受理の倍率}倍のもとの場面が走査の下端{}でも保持しない", 走査する傾きの正接[0]);
        });
        let 二倍の上限 = 保持できる傾きの上限(許容差を二倍にする長さ, 受理の倍率).unwrap_or_else(|| {
            panic!(
                "受理{受理の倍率}倍の許容差が二倍の場面が走査の下端{}でも保持しない",
                走査する傾きの正接[0]
            );
        });
        assert!(
            (もとの上限 - 二倍の上限).abs() < 境界が動いたと見なす差,
            "受理{受理の倍率}倍で許容差を二倍にすると保持できる傾きの上限が{もとの上限}から{二倍の上限}へ動いた"
        );
    }
}
