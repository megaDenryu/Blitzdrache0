//! 解けたと見なす許容差の大きさが、保持と滑走の境界を動かさないことの試験(判断13の2026-09-12の実装の細目の
//! 反証(4)(b))。担当するのは、坂と箱をまとめて坂の面の法線の向きへ動かし、許容差が2倍になる場面で保持できる傾きの
//! 上限が0.01以上動かないことを、受理の許容差の倍率0.5倍・1倍・2倍のそれぞれで固定することである。許容差は誤差の
//! 上限ではなく「ここまで残っていれば解けたものとして扱う」という取り決めであるため、取り決めの幅が物理の結果を
//! 変えない範囲を検査で固定する必要がある。
//! 振り方に法線の向きの平行移動を使うのは、許容差が接触点の世界座標の表現の刻みで決まるためである。坂の中心から
//! 接触点までの長さだけ動かすと座標が2倍になり、走査する傾きの範囲では全部の座標が次の2の冪の帯へ移って刻みが
//! ちょうど2倍になる。この振り方は座標そのものの表せる細かさも同時に粗くするため、許容差だけを単独で振る検査は
//! 受理の倍率を差し替える `slope_tolerance_scale_tests` が持つ。この試験は両方を重ねて振る。
//! 走査の下端を0.50にするのは、既存の27組(`slope_tests`)が固定する正接の下限が0.50だからである。0.50未満は
//! この試験の期待値から外し、表を綴る計器 `tolerance_boundary_record` が受け持つ。0.45から0.49までの行は、
//! 受理の許容差に対する接線変位の比 C_t/δ が1から3程度の帯にあり、混合連立が「表現の精度が不足した」で退避の枝へ
//! 落ちることの累積で分類が動きうる。その退避の機構は Issue #99 が所有し、Issue #59 は直さない(記録の表27・表32)。
//! 上端を0.55にするのは、完了条件が正接0.55の保持を要求するためである。
//! 走らせ方は `tolerance_boundary_scan` が持ち、行ごとの許容差と残差の関係は`normal_tangential_system/tolerance_tests`が固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use super::tolerance_boundary_scan::許容差の境界の走査;

// 下端は27組が固定する正接の下限と同じであり、上端は完了条件の正接0.55である。
const 走査する傾きの正接: &[f32] = &[0.50, 0.51, 0.52, 0.53, 0.54, 0.55];
// 坂の中心から接触点までの長さ。これだけ法線の向きへ動かすと接触点の座標が2倍になり、表現の刻みが2倍になる。
const 許容差を二倍にする長さ: f32 = 20.4999;
// 境界が動いたと見なす差。走査の刻みと同じ大きさである。
const 境界が動いたと見なす差: f32 = 0.01;
const 振る受理の倍率: &[f32] = &[0.5, 1.0, 2.0];

fn 保持できる傾きの上限(法線の向きへ動かす長さ: f32, 受理の倍率: f32) -> Option<f32> {
    許容差の境界の走査::動かす長さと受理の倍率から生成する(法線の向きへ動かす長さ, 受理の倍率)
        .下端から連続して保持する最後の正接(走査する傾きの正接)
}

#[test]
fn 許容差が二倍になる場面でも保持できる傾きの上限が動かない() {
    for &受理の倍率 in 振る受理の倍率 {
        let もとの上限 = 保持できる傾きの上限(0.0, 受理の倍率).unwrap_or_else(|| {
            panic!("受理{受理の倍率}倍のもとの場面が走査の下端{}でも保持しない", 走査する傾きの正接[0]);
        });
        let 二倍の上限 = 保持できる傾きの上限(許容差を二倍にする長さ, 受理の倍率).unwrap_or_else(|| {
            panic!(
                "受理{受理の倍率}倍の許容差が二倍の場面が走査の下端{}でも保持しない",
                走査する傾きの正接[0]
            );
        });
        assert!(
            (もとの上限 - 二倍の上限).abs() < 境界が動いたと見なす差,
            "受理{受理の倍率}倍で許容差を二倍にすると保持できる傾きの上限が{もとの上限}から{二倍の上限}へ動いた"
        );
    }
}
