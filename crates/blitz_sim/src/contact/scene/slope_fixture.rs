//! 坂の場面の組み立てと読み出し(判断13・判断14の検収)。条件から、坂の直方体とその面へ密着した箱の場面を作り、
//! 坂に沿った変位と下り向きの速さを読む。箱の姿勢を坂と同じにするのは、面と面の接触を作るためである。
//! 鉛直軸まわりに場面ごと回すと、箱の姿勢が鉛直軸まわりに回った配置になり、坂を下る向きも世界の中で回る。
//! 接線の軸の取り方が挙動へ漏れていれば、この回しで結果が変わる。幾何の計算は`slope_geometry`が持つ。
//! 坂に沿った変位と下り向きの速さは場面のメソッドである。どちらも場面の状態を読む操作であり、場面を引数で受ける
//! 自由関数にすると操作の所有者が外から渡される形になるためである(坂の条件は場面が持たない値であるため引数で受ける)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

