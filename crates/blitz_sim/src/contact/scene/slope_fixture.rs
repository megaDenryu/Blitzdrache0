pub(super) const 一刻みの細分数: usize = 8;
const 箱の半分の長さ: f32 = 0.5;
const 坂の半分の長さ: f32 = 20.0;
const 初めの食い込み: f32 = 0.0001;
const 細分の刻み幅の秒: f32 = 1.0 / 480.0;

pub(super) fn 坂の場面を組む(条件: &坂の場面の条件) -> 一つの箱と静的な直方体の場面 {
    let 姿勢 = 条件.坂の姿勢();
    let 面までの高さ = メートル::生成する(坂の半分の長さ + 箱の半分の長さ - 初めの食い込み);
    let 箱の重心 = 世界の位置(0.0, 0.0, 0.0).変位を足す(変位::方向へ進む(条件.坂の面の法線(), 面までの高さ));
    一つの箱と静的な直方体の場面::生成する(&場面の設定 {
        箱の半分の長さ,
        箱の質量: 1.0,
        箱の配置: 配置::生成する(箱の重心, 姿勢),
        箱の初速: 速度::方向へ生成する(条件.坂の下り向き(), メートル毎秒::生成する(条件.下り向きの初速)),
        静的な直方体の配置: 配置::生成する(世界の位置(0.0, 0.0, 0.0), 姿勢),
        静的な直方体の半分の長さ: 坂の半分の長さ,
        表面物性: 表面物性::生成する(
            摩擦係数::生成する(条件.静止摩擦係数).unwrap(),
            摩擦係数::生成する(条件.動摩擦係数).unwrap(),
            反発係数::零(),
        )
        .unwrap(),
        重力: 一様な加速度::成分から生成する(
            メートル毎秒毎秒::生成する(0.0),
            メートル毎秒毎秒::生成する(-重力の大きさ),
            メートル毎秒毎秒::生成する(0.0),
        ),
        細分の刻み幅: 刻み幅::生成する(秒::生成する(細分の刻み幅の秒)).unwrap(),
        反復回数: 4,
        速度段階の巡回数: 4,
        静止摩擦の位置拘束を外すか: 条件.静止摩擦の位置拘束を外すか,
    })
}

/// 箱の重心が初めの位置から坂の下り向きへ動いた長さ。上りへ動けば負である。
pub(super) fn 坂に沿った変位(
    場面: &一つの箱と静的な直方体の場面, 初めの重心: 位置<ワールド>, 条件: &坂の場面の条件
) -> f32 {
    (場面.箱の配置.重心の位置() - 初めの重心).方向に沿う長さ(条件.坂の下り向き()).値()
}

/// 箱の並進速度の坂の下り向きの成分。
pub(super) fn 下り向きの速さ(場面: &一つの箱と静的な直方体の場面, 条件: &坂の場面の条件) -> f32 {
    場面.箱の運動状態.並進速度().方向に沿う成分(条件.坂の下り向き()).値()
}
