//! 坂の場面の組み立てと読み出し(判断13・判断14の検収)。条件から、坂の直方体とその面へ密着した箱の場面を作り、
//! 坂に沿った変位と下り向きの速さを読む。箱の姿勢を坂と同じにするのは、面と面の接触を作るためである。
//! 鉛直軸まわりに場面ごと回すと、箱の姿勢が鉛直軸まわりに回った配置になり、坂を下る向きも世界の中で回る。
//! 接線の軸の取り方が挙動へ漏れていれば、この回しで結果が変わる。幾何の計算は`slope_geometry`が持つ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, メートル毎秒, メートル毎秒毎秒, ワールド, 位置, 変位, 秒, 速度};

use super::super::friction_coefficient::摩擦係数;
use super::super::restitution_coefficient::反発係数;
use super::super::surface_property::表面物性;
use super::scene_geometry::世界の位置;
use super::scene_settings::場面の設定;
use super::slope_geometry::{坂の場面の条件, 重力の大きさ};
