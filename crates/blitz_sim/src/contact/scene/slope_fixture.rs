pub(super) const 一刻みの細分数: usize = 8;
const 箱の半分の長さの値: f32 = 0.5;
const 坂の半分の長さの値: f32 = 20.0;
const 初めの食い込み: f32 = 0.0001;
const 細分の刻み幅の秒: f32 = 1.0 / 480.0;

// 判断19の品質の設定。位置の反復回数2と速度段階の巡回数4の由来は正本の判断19の実装の細目にある。
const 既定の位置の反復回数: u32 = 2;
const 速度段階の巡回数: u32 = 4;

pub(super) fn 坂の場面を組む(条件: &坂の場面の条件) -> 一つの箱と静的な直方体の場面 {
    坂の場面を位置の反復回数で組む(条件, 既定の位置の反復回数)
}

/// 解けたと見なす許容差だけを振った坂の場面。世界座標も相対の配置も変えず、解法の取り決めの幅だけを変える。
pub(super) fn 坂の場面を許容差の倍率で組む(
    条件: &坂の場面の条件,
    許容差の倍率: 解けたと見なす許容差の倍率,
) -> 一つの箱と静的な直方体の場面 {
    場面を組む(条件, 既定の位置の反復回数, メートル::生成する(0.0), 許容差の倍率)
}

/// 坂と箱をまとめて坂の面の法線の向きへ動かした場面。世界の原点からの距離だけが変わり、坂と箱の相対の配置は
/// 変わらない。接触点の座標の表現の刻みが変わるため、解けたと見なす許容差の大きさを場面ごと振るのに使う。
pub(super) fn 坂の場面を法線の向きへ動かして組む(
    条件: &坂の場面の条件,
    法線の向きへ動かす長さ: f32,
) -> 一つの箱と静的な直方体の場面 {
    場面を組む(
        条件,
        既定の位置の反復回数,
        メートル::生成する(法線の向きへ動かす長さ),
        解けたと見なす許容差の倍率::既定(),
    )
}

// 位置の反復回数だけを変えた坂の場面。反復回数と法線の乗数の合計の関係を測る検査が読む。
pub(super) fn 坂の場面を位置の反復回数で組む(
    条件: &坂の場面の条件,
    位置の反復回数: u32,
) -> 一つの箱と静的な直方体の場面 {
    場面を組む(条件, 位置の反復回数, メートル::生成する(0.0), 解けたと見なす許容差の倍率::既定())
}

fn 場面を組む(
    条件: &坂の場面の条件,
    位置の反復回数: u32,
    法線の向きへ動かす長さ: メートル,
    許容差の倍率: 解けたと見なす許容差の倍率,
) -> 一つの箱と静的な直方体の場面 {
    let 姿勢 = 条件.坂の姿勢();
    let 面までの高さ = メートル::生成する(坂の半分の長さの値 + 箱の半分の長さの値 - 初めの食い込み);
    let 坂の中心 = 世界の位置(0.0, 0.0, 0.0).変位を足す(変位::方向へ進む(条件.坂の面の法線(), 法線の向きへ動かす長さ));
    let 箱の重心 = 坂の中心.変位を足す(変位::方向へ進む(条件.坂の面の法線(), 面までの高さ));
    一つの箱と静的な直方体の場面::生成する(&場面の設定 {
        箱の半分の長さ: メートル::生成する(箱の半分の長さの値),
        箱の質量: キログラム::生成する(1.0).unwrap(),
        箱の配置: 配置::生成する(箱の重心, 姿勢),
        箱の初速: 速度::方向へ生成する(条件.坂の下り向き(), メートル毎秒::生成する(条件.下り向きの初速)),
        静的な直方体の配置: 配置::生成する(坂の中心, 姿勢),
        静的な直方体の半分の長さ: メートル::生成する(坂の半分の長さの値),
        表面物性: 表面物性::生成する(条件.静止摩擦係数, 条件.動摩擦係数, 反発係数::零()).unwrap(),
        重力: 一様な加速度::成分から生成する(
            メートル毎秒毎秒::生成する(0.0),
            メートル毎秒毎秒::生成する(-重力の大きさ),
            メートル毎秒毎秒::生成する(0.0),
        ),
        細分の刻み幅: 刻み幅::生成する(秒::生成する(細分の刻み幅の秒)).unwrap(),
        解く品質: 接触を解く品質の設定::生成する(位置の反復回数, 速度段階の巡回数).unwrap(),
        静止摩擦の解き方: 条件.静止摩擦の解き方,
        解けたと見なす許容差の倍率: 許容差の倍率,
    })
}

impl 一つの箱と静的な直方体の場面 {
    // 箱の重心が初めの位置から坂の下り向きへ動いた長さ。上りへ動けば負である。
    pub(super) fn 坂に沿った変位(&self, 初めの重心: 位置<ワールド>, 条件: &坂の場面の条件) -> f32 {
        (self.箱の配置.重心の位置() - 初めの重心).方向に沿う長さ(条件.坂の下り向き()).値()
    }

    // 箱の並進速度の坂の下り向きの成分。
    pub(super) fn 下り向きの速さ(&self, 条件: &坂の場面の条件) -> f32 {
        self.箱の運動状態.並進速度().方向に沿う成分(条件.坂の下り向き()).値()
    }
}
