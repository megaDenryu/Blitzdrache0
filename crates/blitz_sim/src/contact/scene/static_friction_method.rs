//! 場面が静止摩擦をどう解くかの選択(判断13の検収の材料)。既定の1つと、欠陥を踏むための反証の2つを持つ。
//! 真偽値を2つ並べずに列挙で持つのは、3つが同時に成り立たない排他の選択だからである。
//! 反証はどちらも「その工程を外すと定量の基準が落ちること」を検査で示すためにあり、本番の工程には無い。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

/// 場面の細分の反復が静止摩擦へ使う解き方。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 場面の静止摩擦の解き方 {
    /// 既定。接触点集合1つの接線を1つの連立として同時に解く。
    接触点集合の接線を同時に解く,
    /// 反証。接触点1つずつを順に射影し、その補正を次の点の前に配置へ適用する。
    接触点ごとに接線を順に射影する,
    /// 反証。静止摩擦の位置拘束そのものを外し、押し戻した点を滑走中として速度段階へ渡す。
    静止摩擦の位置拘束を外す,
}
