//! 粘着の候補が解けなかったときに、その連立方程式から読む量(Issue #59の第4段階の段階A3。試験と計器の専用)。
//! 解く工程(`substep_sticking_candidate`)から分けているのは、あちらが解いて確定する工程であり、こちらが解けなかった
//! 連立方程式の中身を綴るための読み取りだからである。
//! 読むのは、結末の綴りと、法線の行の本数と、接線の行ごとの錨からの接線変位 C_t と解けたと見なす許容差 δ である。
//! 接線の行が0本なら、精度の不足は法線の行の側で起きており、接線の δ の話ではない。行が在るなら C_t と δ の大小が、
//! 行を積むかどうかの閾値(設計候補(i'))がその行を落とすはずだったかを言う。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::normal_tangential_system::{受理の契約を破った理由, 接触点集合の法線と接線の連立方程式};

/// 粘着の候補が解けなかった1つの連立方程式の読み取り。
pub(super) struct 解けなかった連立方程式の読み取り {
    pub(super) 結末の綴り: &'static str,
    pub(super) 受理の破れの残差: String, // 受理の判定が破れた行の残差と許容差の綴り。他の結末では空
    pub(super) 法線の行の本数: usize,
    pub(super) 接線の行ごとの接線変位と許容差: Vec<(f64, f64)>,
}

impl 解けなかった連立方程式の読み取り {
    /// 受理の判定が数値の契約を破った連立方程式の読み取り。破った契約の名前と、その行の残差と許容差を持つ。
    pub(super) fn 連立方程式と受理の破れから読む(
        連立方程式: &接触点集合の法線と接線の連立方程式,
        理由: &受理の契約を破った理由,
    ) -> Self {
        Self {
            受理の破れの残差: 理由.残差の綴り(),
            ..Self::連立方程式と結末から読む(連立方程式, 理由.契約の名前())
        }
    }

    pub(super) fn 連立方程式と結末から読む(
        連立方程式: &接触点集合の法線と接線の連立方程式, 結末の綴り: &'static str
    ) -> Self {
        Self {
            結末の綴り,
            受理の破れの残差: String::new(),
            法線の行の本数: (0..連立方程式.点の数())
                .filter(|番号| 連立方程式.法線の一行を読む(*番号).is_some())
                .count(),
            接線の行ごとの接線変位と許容差: (0..連立方程式.点の数())
                .filter_map(|番号| 連立方程式.接線の一行を読む(番号))
                .map(|一行| (f64::from(一行.接線変位の長さ().値()), f64::from(一行.勾配().解けたと見なす許容差().値())))
                .collect(),
        }
    }

    /// 積んだ接線の行のうち、接線変位が許容差の内側であった行の本数。設計候補(i')が落とすはずだった行である。
    pub(super) fn 許容差の内側の接線の行の本数(&self) -> usize {
        self.接線の行ごとの接線変位と許容差
            .iter()
            .filter(|(接線変位, 許容差)| 接線変位 <= 許容差)
            .count()
    }

    /// 表へ綴る形。
    pub(super) fn 綴り(&self) -> String {
        let 行ごと: Vec<String> = self
            .接線の行ごとの接線変位と許容差
            .iter()
            .map(|(接線変位, 許容差)| format!("C_t={接線変位:.3e}/δ={許容差:.3e}"))
            .collect();
        format!(
            "結末={}{} 法線の行={}本 接線の行={}本(うち許容差の内側{}本) [{}]",
            self.結末の綴り,
            self.受理の破れの残差,
            self.法線の行の本数,
            self.接線の行ごとの接線変位と許容差.len(),
            self.許容差の内側の接線の行の本数(),
            行ごと.join(" ")
        )
    }
}
