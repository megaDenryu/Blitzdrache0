//! 場面の細分の中の非貫通の同時解法(判断12の接触点集合の単位の試験専用の実装)。担当するのは、接触点集合1つの
//! 全部の行を1つの連立として解き、点ごとの補正を合計してから配置へ1度だけ適用することである。
//! 静止摩擦の射影(`substep_static_friction`)から分けているのは、こちらが法線の連立という別の工程だからである。
//! 点ごとに配置へ適用しないのは、その適用が次の点の腕と有効逆質量を変え、面と面の接触で剛体が点の間を往復する
//! ためである。往復は反復回数を増やすほど法線の乗数の合計を真の法線力積から離す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_collision::contact_set::接触点の上限;

use super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::super::non_penetration::接触点集合の法線の同時解;
use super::substep_harness::一つの箱と静的な直方体の場面;
use crate::rigid_xpbd::{予測の状態, 姿勢自由度の参加者, 姿勢自由度の補正};

impl 一つの箱と静的な直方体の場面 {
    // 接触点集合1つの非貫通を同時に解く。
    // 注意: 行の受け皿の長さは接触点集合が持てる接触点の上限である。これを超える集合は衝突数学層の不変条件の破れであり、
    // 添字の範囲外として落ちる。
    pub(super) fn 接触点集合の非貫通を同時に解く(
        &self,
        接触点集合: &mut [剛体と静的世界の接触拘束],
        射影の前の予測: 予測の状態,
    ) -> 予測の状態 {
        let 参加者 = 姿勢自由度の参加者::動的(*射影の前の予測.配置(), &self.箱の質量特性);
        let Some(先頭) = 接触点集合.first() else {
            return 射影の前の予測;
        };
        let mut 行 = [先頭.同時解法の一行にする(&参加者); 接触点の上限];
        for (番号, 拘束) in 接触点集合.iter().enumerate() {
            行[番号] = 拘束.同時解法の一行にする(&参加者);
        }
        let 解 = 接触点集合の法線の同時解::接触点集合を同時に解く(&行[..接触点集合.len()]);
        let mut 補正の合計 = 姿勢自由度の補正::零();
        for (番号, 拘束) in 接触点集合.iter_mut().enumerate() {
            let 乗数の増分 = 解.一行の乗数の増分(番号);
            let (剛体の側の補正, _) = 行[番号].乗数の増分を二つの補正へ分配する(乗数の増分);
            補正の合計 = 補正の合計.合わせる(&剛体の側の補正);
            拘束.同時解法の乗数の増分を取り込む(&行[番号], 乗数の増分);
        }
        射影の前の予測.補正を適用する(&補正の合計)
    }
}
