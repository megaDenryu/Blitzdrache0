//! 残差の分離が細分ごとに何をしているかを綴る計器(判断24の第2段階の診断)。合否は判定せず、表を作るだけである。
//! 判定する反証は`residual_separation_tests`が持ち、この計器はその閾値も場面も動かさない。
//! 綴るのは、確定した位置のx成分とy成分のビット列・坂に沿った変位とその1細分の変化・細分の終わりに測った残差・
//! 残差の1細分の変化・仮の補正を引く前と引いた後の下り向きの速さ・粘着の候補を確定した点の数である。
//! ビット列を綴るのは、位置の変化が単精度の表現の刻みの整数倍で上下しているかを見るためである。刻みの整数倍で
//! 上下していて、引いた後の速さが零に近いのに次の細分で位置がまた1刻み動くなら、往復は速度でなく位置の側にある。
//! 実行は `cargo test -p blitz_sim --release 残差の分離が細分ごとに何をしているかを記録する -- --ignored --nocapture` である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::super::friction_coefficient::摩擦係数;
use super::residual_separation::場面の残差の分離;
use super::slope_fixture::坂の場面を組む;
use super::slope_geometry::坂の場面の条件;
use super::static_friction_method::場面の静止摩擦の解き方;

const 綴る細分の本数: usize = 17;

fn 測る条件(傾きの正接: f32) -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    }
}

fn 一つの経路を綴る(傾きの正接: f32, 分離: 場面の残差の分離) {
    let 条件 = 測る条件(傾きの正接);
    let mut 場面 = 坂の場面を組む(&条件);
    場面.残差の分離 = 分離;
    let 初めの重心 = 場面.箱の配置.重心の位置();
    let 刻み幅の秒 = 場面.刻み幅.秒().値();
    let mut 前の変位 = 0.0;
    println!("[正接{傾きの正接} {分離:?}] 刻み幅={刻み幅の秒:.6e}秒");
    for 番号 in 0..綴る細分の本数 {
        場面.一細分進める();
        let 観測 = 場面.直前の細分の観測.残差の観測;
        let 位置 = 場面.箱の配置.重心の位置();
        let 変位 = 場面.坂に沿った変位(初めの重心, &条件);
        let 引く前 = 観測.仮の補正を引く前の並進速度.方向に沿う成分(条件.坂の下り向き()).値();
        println!(
            "  細分{番号} x=0x{:08x} y=0x{:08x} 変位={変位:.6e} 変位の変化={:.6e} 残差={:.4e} 残差の変化={:.4e} 引く前の速さ={引く前:.6e} 引いた後の速さ={:.6e} 確定した点={}",
            位置.x().値().to_bits(),
            位置.y().値().to_bits(),
            変位 - 前の変位,
            観測.細分の終わりの残差の最大の長さ.値(),
            観測.残差の変化の最大の長さ.値(),
            場面.下り向きの速さ(&条件),
            観測.粘着の候補を確定した点の数,
        );
        前の変位 = 変位;
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 残差の分離が細分ごとに何をしているかを記録する() {
    一つの経路を綴る(0.50, 場面の残差の分離::残差の変化を速度から除く);
    一つの経路を綴る(0.50, 場面の残差の分離::残差の変化を速度へ運ばせる);
}
