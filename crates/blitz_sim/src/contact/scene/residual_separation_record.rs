//! 残差の分離が細分ごとに何をしているかを綴る計器(判断24の第2段階の診断)。合否は判定せず、表を作るだけである。
//! 判定する反証は`residual_separation_tests`が持ち、この計器はその閾値も場面も動かさない。
//! 綴るのは、除く経路と運ばせる経路のそれぞれについて、細分ごとの滑走中の点の数・残差の変化を持った点の数・
//! 変化の最大の長さ・円錐の比・位置から再構成した下り向きの速さである。
//! 変化の長さと速さを並べるのは、打ち消したい量が速さの飛びと同じ桁であるかを確かめるためである。同じ桁で
//! ありながら反転の数が減らないなら、周期の原因は残差の持ち越しの外にある。
//! 実行は `cargo test -p blitz_sim --release 残差の分離が細分ごとに何をしているかを記録する -- --ignored --nocapture` である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::super::friction_coefficient::摩擦係数;
use super::residual_separation::場面の残差の分離;
use super::slope_fixture::坂の場面を組む;
use super::slope_geometry::坂の場面の条件;
use super::static_friction_method::場面の静止摩擦の解き方;

const 綴る細分の本数: usize = 64;

fn 測る条件(傾きの正接: f32) -> 坂の場面の条件 {
    坂の場面の条件 {
        傾きの正接,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
    }
}

fn 一つの経路を綴る(傾きの正接: f32, 分離: 場面の残差の分離) {
    let 条件 = 測る条件(傾きの正接);
    let mut 場面 = 坂の場面を組む(&条件);
    場面.残差の分離 = 分離;
    println!("[正接{傾きの正接} {分離:?}]");
    let mut 反転 = 0;
    let mut 前の速さ = 0.0;
    for 番号 in 0..綴る細分の本数 {
        場面.一細分進める();
        let 観測 = 場面.直前の細分の観測;
        let 速さ = 場面.下り向きの速さ(&条件);
        if 番号 > 0 && 前の速さ * 速さ < 0.0 {
            反転 += 1;
        }
        前の速さ = 速さ;
        let 比 = f64::from(観測.接線の乗数の合力の大きさ.値()) / f64::from(観測.法線の乗数の合計.値()).max(1.0e-30);
        println!(
            "  細分{番号} 滑走中={} 変化を持つ点={} 変化の最大={:.4e} 比={:.6} 速さ={:.4e}",
            観測.滑走中の接触点の数,
            観測.残差の変化が在る点の数,
            観測.残差の変化の最大の長さ.値(),
            比,
            速さ,
        );
    }
    println!("  符号の反転={反転}回");
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 残差の分離が細分ごとに何をしているかを記録する() {
    for 傾きの正接 in [0.50, 0.55] {
        一つの経路を綴る(傾きの正接, 場面の残差の分離::残差の変化を速度から除く);
        一つの経路を綴る(傾きの正接, 場面の残差の分離::残差の変化を速度へ運ばせる);
    }
}
