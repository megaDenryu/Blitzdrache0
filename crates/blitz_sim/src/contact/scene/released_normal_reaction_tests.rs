//! 法線反力を解放された接触点の古い接線の乗数が、接触点集合に残らないことの検査(判断13)。担当するのは2つである。
//! 解放された点の乗数が円錐の合力 ‖Σλ_t‖ へ入らないこと(残ると集合の全体が誤って滑走中へ落ちる)、
//! 集合が円錐を超えて仮の補正を捨てる反復でも、解放された点の乗数だけは零へ確定することである。
//! 材料は`sticking_candidate_fixture`の「保持している最中に1点が離れる細分」であり、離れた点にだけ円錐の半径を
//! 超える大きさの古い接線の乗数を持たせる。混合の連立は法線の乗数を接線と同時に決めるため、法線反力が無い点で
//! あるかは有効集合が定まった後に決まる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use super::super::static_friction::接線のラグランジュ乗数;
use super::sticking_candidate_fixture::{一点が離れた四隅の接触点集合, 平らな床の場面と予測, 離れる点の番号};

// 円錐の内側に収まる滑り。残る3点の接線の乗数がこの長さから決まる。
const 円錐の内側に収まる滑らせる長さ: f32 = 1.0e-6;
// 円錐を超える滑り。残る3点の接線の乗数だけで静止摩擦係数0.5の円錐を超える。
const 円錐を超える滑らせる長さ: f32 = 1.0e-3;
// 離れた点に残す古い接線の乗数。3点の法線の乗数が作る円錐の半径より大きい。
const 円錐の半径を超える古い接線の乗数: f32 = 1.0;

#[test]
fn 法線反力を解放された点の古い接線の乗数は円錐の合力に入らない() {
    let (場面, 予測) = 平らな床の場面と予測();
    let mut 接触点集合 = 一点が離れた四隅の接触点集合(&場面, &予測, 円錐の内側に収まる滑らせる長さ, 円錐の半径を超える古い接線の乗数);
    場面.接触点集合の粘着の候補を解く(&mut 接触点集合, 予測);
    assert!(
        !接触点集合[0].静止摩擦の解の状態().滑走中か(),
        "法線反力の無い点の古い接線の乗数が合力へ入り、集合の全体が滑走中へ落ちた"
    );
    assert_eq!(
        接触点集合[離れる点の番号].静止摩擦の解の状態().接線のラグランジュ乗数(),
        接線のラグランジュ乗数::零(),
        "法線反力の無い点に古い接線の乗数が残った"
    );
}

#[test]
fn 円錐を超えて仮の補正を捨てる反復でも法線反力の無い点の乗数は零へ確定する() {
    let (場面, 予測) = 平らな床の場面と予測();
    let mut 接触点集合 = 一点が離れた四隅の接触点集合(&場面, &予測, 円錐を超える滑らせる長さ, 円錐の半径を超える古い接線の乗数);
    場面.接触点集合の粘着の候補を解く(&mut 接触点集合, 予測);
    assert!(接触点集合[0].静止摩擦の解の状態().滑走中か(), "円錐を超えた集合が滑走中と印されていない");
    assert_eq!(
        接触点集合[0].静止摩擦の解の状態().接線のラグランジュ乗数(),
        接線のラグランジュ乗数::零(),
        "捨てるべき仮の補正の側の乗数が確定してしまった"
    );
    assert_eq!(
        接触点集合[離れる点の番号].静止摩擦の解の状態().接線のラグランジュ乗数(),
        接線のラグランジュ乗数::零(),
        "円錐を超えた反復で法線反力の無い点の乗数が解放されなかった"
    );
}
