const 食い込ませる高さ: f32 = -0.05; // 法線の乗数を正にする貫通。有効逆質量1であるため乗数は0.05になる
const 離す高さ: f32 = 10.0; // 1回の射影で法線の乗数を0まで解放できる隔たり
const 円錐の半径を超える接線の乗数: f32 = 0.1; // 法線の乗数0.05と静止摩擦係数0.5が作る半径0.025を超える大きさ

// 平らな床の上の箱の場面。接触点集合の静止摩擦の射影が読む質量特性と予測の配置だけをここから採る。
fn 平らな場面と予測() -> (一つの箱と静的な直方体の場面, 予測の状態) {
    let 場面 = 坂の場面を組む(&坂の場面の条件 {
        傾きの正接: 0.0,
        鉛直軸まわりの回し: 0.0,
        静止摩擦係数: 摩擦係数::生成する(0.5).unwrap(),
        動摩擦係数: 摩擦係数::生成する(0.4).unwrap(),
        下り向きの初速: 0.0,
        静止摩擦の位置拘束を外すか: false,
    });
    let (_, 予測, _) = 場面
        .予測器
        .動的剛体を予測する(&場面.箱の配置, &場面.箱の運動状態, &場面.箱の質量特性, &一刻みの入力::無し());
    (場面, 予測)
}

fn 接平面の接線の乗数(大きさ: f32) -> 接線のラグランジュ乗数 {
    接線のラグランジュ乗数::零().向きへの増分を足す(
        方向::生成する(1.0, 0.0, 0.0).unwrap(),
        ラグランジュ乗数::長さを逆質量で割って生成する(メートル::生成する(大きさ), 逆キログラム::生成する(1.0).unwrap()),
    )
}

// 法線の乗数が正のまま残る接触点。接線の乗数は指定の大きさを持たせる。
fn 法線反力が在る接触点(接線の乗数の大きさ: f32) -> 剛体と静的世界の接触拘束 {
    let mut 拘束 = 剛体と静的世界の接触拘束::引数と刻み幅から生成する(剛体と静的世界の基本の引数(), 試験の刻み幅()).unwrap();
    拘束.一回射影する(&高さの参加者(食い込ませる高さ));
    拘束.静止摩擦の仮の乗数を確定する(接平面の接線の乗数(接線の乗数の大きさ));
    assert!(
        拘束.法線のラグランジュ乗数() > ラグランジュ乗数::零(),
        "材料の法線の乗数が正になっていない"
    );
    拘束
}

// 反復1で法線と接線の乗数を得た後、反復2で隔たりが開いて法線の乗数を0へ解放された接触点。
fn 法線反力を解放された接触点() -> 剛体と静的世界の接触拘束 {
    let mut 拘束 = 法線反力が在る接触点(円錐の半径を超える接線の乗数);
    拘束.一回射影する(&高さの参加者(離す高さ));
    assert_eq!(
        拘束.法線のラグランジュ乗数(),
        ラグランジュ乗数::零(),
        "材料の法線の乗数が解放されていない"
    );
    拘束
}

#[test]
fn 法線反力を解放された点の古い接線の乗数は円錐の合力に入らない() {
    let (場面, 予測) = 平らな場面と予測();
    let mut 接触点集合 = [法線反力が在る接触点(0.0), 法線反力を解放された接触点()];
    場面.接触点集合の静止摩擦を射影する(&mut 接触点集合, 予測);
    assert!(
        !接触点集合[0].静止摩擦の解の状態().滑走中か(),
        "法線反力の無い点の古い接線の乗数が合力へ入り、集合の全体が滑走中へ落ちた"
    );
    assert_eq!(
        接触点集合[1].静止摩擦の解の状態().接線のラグランジュ乗数(),
        接線のラグランジュ乗数::零(),
        "法線反力の無い点に古い接線の乗数が残った"
    );
}

#[test]
fn 円錐を超えて仮の補正を捨てる反復でも法線反力の無い点の乗数は零へ確定する() {
    let (場面, 予測) = 平らな場面と予測();
    let mut 接触点集合 = [法線反力が在る接触点(円錐の半径を超える接線の乗数), 法線反力を解放された接触点()];
    場面.接触点集合の静止摩擦を射影する(&mut 接触点集合, 予測);
    assert!(接触点集合[0].静止摩擦の解の状態().滑走中か(), "円錐を超えた集合が滑走中と印されていない");
    assert_eq!(
        接触点集合[0].静止摩擦の解の状態().接線のラグランジュ乗数(),
        接平面の接線の乗数(円錐の半径を超える接線の乗数),
        "捨てるべき仮の補正の側の乗数まで書き換わった"
    );
    assert_eq!(
        接触点集合[1].静止摩擦の解の状態().接線のラグランジュ乗数(),
        接線のラグランジュ乗数::零(),
        "円錐を超えた反復で法線反力の無い点の乗数が解放されなかった"
    );
}
