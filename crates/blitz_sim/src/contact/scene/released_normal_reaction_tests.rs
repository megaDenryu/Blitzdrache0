//! 法線反力を解放された接触点の古い接線の乗数が、接触点集合に残らないことの検査(判断13)。担当するのは2つである。
//! 解放された点の乗数が円錐の合力 ‖Σλ_t‖ へ入らないこと(残ると集合の全体が誤って滑走中へ落ちる)、
//! 集合が円錐を超えて仮の補正を捨てる反復でも、解放された点の乗数だけは零へ確定することである。
//! 材料は反復1で法線と接線の乗数が正になり、反復2で隔たりが開いて法線の乗数が0へ解放される接触点である。
//! この状態遷移は判断12の乗数の解放を入れて初めて通るようになった。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

