//! 材質の対: 混合則の上書き表の鍵になる2つの材質の識別子の組(判断15)。生成が小さい方を先に置いて正規化するため、
//! 引数の順を入れ替えて登録しても参照しても同じ項に当たる。これが混合則の可換性を上書き表の側で守る仕組みである。
//! 同じ材質どうしの対(木と木)も正当な鍵であり、2つの識別子が等しくてもよい。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断15: 接触物性は両表面の物性から混合則で決め、既定則と材質対の上書き表を持つ」

use super::material_id::材質の識別子;

/// 上書き表の鍵。2つの材質の識別子を昇順に並べた組である。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 材質の対 {
    小さい方: 材質の識別子,
    大きい方: 材質の識別子,
}

impl 材質の対 {
    /// 2つの識別子を昇順へ並べ替えて作る。どの組み合わせも正当な鍵であるため検査は無い。
    pub fn 生成する(第1: 材質の識別子, 第2: 材質の識別子) -> Self {
        if 第1 <= 第2 {
            Self {
                小さい方: 第1,
                大きい方: 第2,
            }
        } else {
            Self {
                小さい方: 第2,
                大きい方: 第1,
            }
        }
    }

    /// 昇順に並べたときに先に来る材質の識別子。
    pub fn 小さい方(&self) -> 材質の識別子 {
        self.小さい方
    }

    /// 昇順に並べたときに後に来る材質の識別子。
    pub fn 大きい方(&self) -> 材質の識別子 {
        self.大きい方
    }
}
