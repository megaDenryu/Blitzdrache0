//! 接触点1つを静止摩擦の連立へ入れようとした結果(判断13)。入れなかった理由の枝を持つのは、理由ごとに接線の
//! 乗数の扱いが違うためである(零へ解放する点と、既存の乗数を保つ点に分かれる)。
//! 作った行そのものはこの列挙が持たず、連立の側が点の番号で持つ。行は2つの錨と向きを束ねた大きな値であり、
//! 理由だけの枝と同じ列挙へ入れると、枝の大きさが揃わない列挙が接触点の数だけ受け皿に並ぶためである。
//! 「既にこの細分で滑走中」は、その接触点集合がこの細分で既に円錐を超えている枝である。超えた細分では錨を
//! 置き直しているため、置き直した錨からの新しい接線変位で解き直すと位置の静止摩擦が復活してしまう。
//! 「法線反力が無い」は、法線の有効集合から外れた接触点である。混合の連立は法線の乗数を接線と同時に決めるため、
//! この枝は行を積む時点では決まらず、有効集合が定まった後に呼び出し側が上書きして与える。実在しない法線反力で
//! 円錐の判定(μ_s λ_n)が効くことを防ぐ。この点の接線の乗数は集合の判定に依らず零へ解放する。
//! 「接線変位が零」は戻す先が既に一致している点であり、連立へ入れずに既存の接線の乗数を保つ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

/// 接触1点を静止摩擦の連立へ入れた結果。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 静止摩擦の連立へ点を入れた結果 {
    /// 錨からの接線変位を零へ戻す行を連立へ積んだ。乗数の増分は集合の連立を解いて決まる。
    一行を積んだ,
    /// この接触点集合はこの細分で既に円錐を超えて滑走中である。位置の静止摩擦はこの細分ではもう効かせない。
    既にこの細分で滑走中,
    /// 2つの錨の接線方向の隔たりが零であり、零へ戻す先が既に一致している。
    接線変位が零,
    /// その細分の法線のラグランジュ乗数が0であり、法線反力が存在しない。
    法線反力が無い,
    /// 両方の参加者が静的か運動学的で、どちらも動かせない。
    両方が動かせない,
}
