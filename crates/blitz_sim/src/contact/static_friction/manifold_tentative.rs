//! 接触点集合の連立を解いた後の、点ごとの仮の接線の乗数と円錐の判定の集計(判断13)。
//! 集計の型(`manifold_cone`)から分けているのは、あちらが2つの合計だけを持つ判定の材料であるのに対し、
//! こちらが点ごとの仮の値も併せて持ち、確定と解放の両方の宛先になるからである。
//! 円錐を超えたときは仮の補正を集合ごと捨てるが、法線反力が無い点の解放だけはこの集まりから確定させる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_collision::contact_set::接触点の上限;

use super::super::contact_property::接触物性;
use super::manifold_cone::接触点集合の静止摩擦の仮の集計;
use super::tangential_multiplier::接線のラグランジュ乗数;
use super::tentative_point_multiplier::接触点の仮の接線の乗数;
use crate::xpbd::ラグランジュ乗数;

/// 接触点集合1つの仮の乗数の集まり。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触点集合の仮の乗数の集まり {
    点ごとの仮の接線の乗数: [接触点の仮の接線の乗数; 接触点の上限],
    集計: 接触点集合の静止摩擦の仮の集計,
}

impl 接触点集合の仮の乗数の集まり {
    /// 1点も足していない集まり。呼び出し側が接触点集合の走査で点を足していく。
    pub fn 空から始める() -> Self {
        Self {
            点ごとの仮の接線の乗数: [接触点の仮の接線の乗数::集合が円錐の内側なら確定する(
                接線のラグランジュ乗数::零(),
            ); 接触点の上限],
            集計: 接触点集合の静止摩擦の仮の集計::空(),
        }
    }

    /// 接触点1つの仮の接線の乗数と、混合の連立で更新した後の法線の乗数を足す。
    /// 注意: 点の番号が接触点の上限を超える集合は衝突数学層の不変条件の破れであり、添字の範囲外として落ちる。
    pub fn 一点を足す(
        &mut self, 点の番号: usize, 仮の接線の乗数: 接触点の仮の接線の乗数, 更新後の法線の乗数: ラグランジュ乗数
    ) {
        self.点ごとの仮の接線の乗数[点の番号] = 仮の接線の乗数;
        self.集計 = self
            .集計
            .一点の仮の乗数を足した集計(更新後の法線の乗数, 仮の接線の乗数.確定する接線の乗数());
    }

    /// 接線の乗数の合力がクーロン円錐の内側に留まっているか。偽なら接触点集合の全部の点が滑走へ移る。
    pub fn 円錐の内側か(&self, 接触物性: 接触物性) -> bool {
        self.集計.円錐の内側か(接触物性)
    }

    pub fn 一点の仮の接線の乗数(&self, 点の番号: usize) -> 接触点の仮の接線の乗数 {
        self.点ごとの仮の接線の乗数[点の番号]
    }
}
