//! 静止摩擦の射影の試験が共有する材料(判断13)。担当するのは、腕が零の錨(重心そのもの)を持つ剛体の側と、
//! 接平面の中で指定の向きへ接線変位の長さだけ離れた静的世界の側を作ることである。腕を零にするのは、
//! 一般化逆質量が逆質量1に等しくなり、円錐の判定を手計算で追えるようにするためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{
    キログラム, キログラム平方メートル, クォータニオン, メートル, ワールド, 位置, 変位, 方向, 逆キログラム
};

use super::super::contact_projection_participant::接触の射影に参加する点;
use super::super::contact_property::接触物性;
use super::super::friction_coefficient::摩擦係数;
use super::super::restitution_coefficient::反発係数;
use super::result::静止摩擦の一回の射影の結果;
use super::substep_state::静止摩擦の一細分の解の状態;
use crate::rigid_body::{主慣性, 主慣性と主軸, 姿勢, 質量特性, 配置};
use crate::rigid_xpbd::姿勢自由度の参加者;
use crate::xpbd::ラグランジュ乗数;

pub(super) const 接線変位の長さ: f32 = 0.01;
pub(super) const 静止摩擦係数の値: f32 = 0.5;

pub(super) fn 下向きの接触法線() -> 方向<ワールド> {
    方向::生成する(0.0, -1.0, 0.0).unwrap()
}

pub(super) fn 試験の接触物性() -> 接触物性 {
    接触物性::生成する(
        摩擦係数::生成する(静止摩擦係数の値).unwrap(),
        摩擦係数::生成する(静止摩擦係数の値).unwrap(),
        反発係数::零(),
    )
    .unwrap()
}

// 重心そのものを錨にした剛体の側。腕が零であるため一般化逆質量は逆質量1に等しく、円錐の判定を手計算で追える。
pub(super) fn 重心を錨にした剛体() -> 接触の射影に参加する点 {
    let 慣性 = キログラム平方メートル::生成する(1.0);
    let 質量特性 = 質量特性::生成する(
        キログラム::生成する(1.0).unwrap(),
        変位::零(),
        主慣性と主軸::生成する(主慣性::生成する(慣性, 慣性, 慣性), クォータニオン::軸が一致する回転()).unwrap(),
    )
    .unwrap();
    let 配置 = 配置::生成する(
        位置::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0)),
        姿勢::恒等(),
    );
    接触の射影に参加する点::剛体の局所点から生成する(姿勢自由度の参加者::動的(配置, &質量特性), 変位::零())
}

// 接平面(x-z)の中で指定の角の向きへ、接線変位の長さだけ離れた静的世界の錨。
pub(super) fn 接平面で回した静的世界の錨(角: f32) -> 接触の射影に参加する点 {
    let (正弦, 余弦) = 角.sin_cos();
    接触の射影に参加する点::静的世界の固定点から生成する(位置::生成する(
        メートル::生成する(接線変位の長さ * 余弦),
        メートル::生成する(0.0),
        メートル::生成する(接線変位の長さ * 正弦),
    ))
}

pub(super) fn 法線の乗数(値: f32) -> ラグランジュ乗数 {
    ラグランジュ乗数::長さを逆質量で割って生成する(メートル::生成する(値), 逆キログラム::生成する(1.0).unwrap())
}

pub(super) fn 一回射影する(角: f32, 法線のラグランジュ乗数: ラグランジュ乗数) -> 静止摩擦の一回の射影の結果 {
    静止摩擦の一細分の解の状態::細分の開始の状態().一回射影する(
        重心を錨にした剛体(),
        接平面で回した静的世界の錨(角),
        下向きの接触法線(),
        試験の接触物性(),
        法線のラグランジュ乗数,
    )
}
