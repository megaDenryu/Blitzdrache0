//! 静止摩擦を一回射影した結果(判断13)。円錐の内側で保持した枝だけが補正を持ち、他の枝では配置も姿勢も変わらない。
//! 「円錐を超えて滑走中になった」は補正を適用しない枝である。呼び出し側の接触拘束が錨を現在の接触点へ置き直し、
//! その細分の滑走中の印を立てる。抵抗は判断14の速度段階の動摩擦が受け持つ。
//! 一度この印が立った接触点は、同じ細分の残りの反復で「既にこの細分で滑走中」を返して補正を返さない。
//! 印が立った後も反復のたびに円錐を判定すると、置き直した錨からの新しい接線変位が円錐の内側に入り、
//! 位置の静止摩擦と速度の動摩擦が同じ細分で二重に効く(実測で滑走の減速度が μ_d でなく μ_s の値になる)。
//! 「法線反力が無い」は、その細分の法線のラグランジュ乗数が0の接触点である。実在しない法線反力で円錐の判定(μ_s λ_n)
//! が効くことを防ぐ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::substep_state::静止摩擦の一細分の解の状態;
use crate::rigid_xpbd::姿勢自由度の補正;

/// 接触1点の静止摩擦を一回射影した結果。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 静止摩擦の一回の射影の結果 {
    /// 接線の乗数がクーロン円錐の内側に留まった。補正を各参加者の予測の状態へ適用する。
    円錐の内側で保持した {
        補正a: 姿勢自由度の補正,
        補正b: 姿勢自由度の補正,
        更新後の解の状態: 静止摩擦の一細分の解の状態,
    },
    /// 接線の乗数がクーロン円錐を超えた。補正は適用せず、錨を置き直して滑走中と印す。
    円錐を超えて滑走中になった {
        更新後の解の状態: 静止摩擦の一細分の解の状態
    },
    /// この細分の前の反復で既に滑走中と印されている。位置の静止摩擦はこの細分ではもう効かせない。
    既にこの細分で滑走中,
    /// 2つの錨の接線方向の隔たりが零であり、零へ戻す先が既に一致している。
    接線変位が零,
    /// その細分の法線のラグランジュ乗数が0であり、法線反力が存在しない。
    法線反力が無い,
    /// 両方の参加者が静的か運動学的で、どちらも動かせない。
    両方が動かせない,
}
