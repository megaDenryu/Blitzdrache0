//! 静止摩擦を接触点1つへ仮に射影した結果(判断13)。仮と呼ぶのは、この結果だけでは補正を確定できないためである。
//! クーロン円錐の判定は接触点集合の単位で行い、集合の全部の点の仮の結果が揃ってから一括で確定するか一括で捨てる。
//! 点ごとに判定して一部だけを適用すると、同じ細分で位置の静止摩擦と速度の動摩擦が二重に効く。
//! 「既にこの細分で滑走中」は、その接触点集合がこの細分で既に円錐を超えている枝である。超えた細分では錨を置き直して
//! いるため、置き直した錨からの新しい接線変位で判定し直すと位置の静止摩擦が復活してしまう。
//! 「法線反力が無い」は、その細分の法線のラグランジュ乗数が0の接触点である。実在しない法線反力で円錐の判定(μ_s λ_n)
//! が効くことを防ぐ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::tangential_multiplier::接線のラグランジュ乗数;
use crate::rigid_xpbd::姿勢自由度の補正;

/// 接触1点の静止摩擦を仮に射影した結果。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 静止摩擦の一回の仮の射影の結果 {
    /// 錨からの接線変位を零へ戻す補正と、その補正まで進めた接線の乗数を求めた。確定するかは接触点集合の判定が決める。
    接線を戻す補正を求めた {
        補正a: 姿勢自由度の補正,
        補正b: 姿勢自由度の補正,
        進めた接線の乗数: 接線のラグランジュ乗数,
    },
    /// この接触点集合はこの細分で既に円錐を超えて滑走中である。位置の静止摩擦はこの細分ではもう効かせない。
    既にこの細分で滑走中,
    /// 2つの錨の接線方向の隔たりが零であり、零へ戻す先が既に一致している。
    接線変位が零,
    /// その細分の法線のラグランジュ乗数が0であり、法線反力が存在しない。
    法線反力が無い,
    /// 両方の参加者が静的か運動学的で、どちらも動かせない。
    両方が動かせない,
}
