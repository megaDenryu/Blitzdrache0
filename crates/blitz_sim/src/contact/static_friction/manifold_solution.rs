//! 接触点集合の接線を同時に解いた結果(判断13)。点ごとの乗数の増分 Δs を持つ。
//! 連立の型(`manifold_system`)から分けているのは、こちらが解いた後に凍る値であり、連立が行を積むあいだ
//! 書き換わる状態を所有するからである。連立へ入らなかった点の増分は零であり、その点の接線の乗数は
//! `接触点の仮の接線の乗数` が枝ごとに決める(既存の乗数を保つ点と、零へ解放する点に分かれる)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_collision::contact_set::接触点の上限;

use crate::xpbd::ラグランジュ乗数;

/// 接触点集合1つの接線を同時に解いた結果。並びは接触点集合の中の点の番号と同じである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触点集合の静止摩擦の同時解 {
    乗数の増分: [ラグランジュ乗数; 接触点の上限],
}

impl 接触点集合の静止摩擦の同時解 {
    pub(super) fn 乗数の増分の一覧から生成する(乗数の増分: [ラグランジュ乗数; 接触点の上限]) -> Self {
        Self { 乗数の増分 }
    }

    /// 指定の点の乗数の増分 Δs。連立へ入らなかった点は零である。
    pub fn 一点の乗数の増分(&self, 点の番号: usize) -> ラグランジュ乗数 {
        self.乗数の増分[点の番号]
    }
}
