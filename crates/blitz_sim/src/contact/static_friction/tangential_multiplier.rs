//! 接線のラグランジュ乗数: 接平面上に横たわる位置の拘束の乗数を、ワールドの3成分で持つ型(判断13)。
//! 円錐の判定を大きさで行う(等方の判定)ために、1次元の乗数を接線の軸ごとに2つ持つのでなく1つのベクトルとして累積する。
//! 接線の軸を固定して2つの1次元の乗数を独立に切り詰める箱近似は、方向によって摩擦の強さが変わるため採らない。
//! 成分をワールドの3つで持つのは、接線の向き t が反復と細分のあいだに接平面の中で回るためであり、
//! 接平面の2次元の基底を固定するとその基底自体が挙動に漏れる。法線の成分は射影が t を接平面上に採ることで0に保たれる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use std::ops::Add;

use blitz_math::{ワールド, 方向};

use crate::xpbd::ラグランジュ乗数;

/// 接触1点がその細分に累積した接線の乗数。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接線のラグランジュ乗数 {
    x成分: ラグランジュ乗数,
    y成分: ラグランジュ乗数,
    z成分: ラグランジュ乗数,
}

impl 接線のラグランジュ乗数 {
    /// 細分の開始の値。法線の乗数と同じく前の細分から引き継がない(判断16の暖機をしない)。
    pub fn 零() -> Self {
        Self {
            x成分: ラグランジュ乗数::零(),
            y成分: ラグランジュ乗数::零(),
            z成分: ラグランジュ乗数::零(),
        }
    }

    /// 向き t へ増分 Δλ_t を足した乗数 λ_t + Δλ_t t。円錐の判定はこの値の大きさで行う。
    pub fn 向きへの増分を足す(&self, 向き: 方向<ワールド>, 増分: ラグランジュ乗数) -> Self {
        Self {
            x成分: self.x成分 + 増分.比で伸ばす(向き.x()),
            y成分: self.y成分 + 増分.比で伸ばす(向き.y()),
            z成分: self.z成分 + 増分.比で伸ばす(向き.z()),
        }
    }

    /// クーロン円錐の判定が μ_s λ_n と比べる大きさ |λ_t|。
    pub fn 大きさ(&self) -> ラグランジュ乗数 {
        ラグランジュ乗数::三成分の大きさを求める(self.x成分, self.y成分, self.z成分)
    }

    // ワールドの3成分。接線の乗数のねじりのモーメントを測る計器が読む口であり、公開面には出さない。
    #[cfg(test)]
    pub(in crate::contact) fn 三つの成分(&self) -> (ラグランジュ乗数, ラグランジュ乗数, ラグランジュ乗数) {
        (self.x成分, self.y成分, self.z成分)
    }
}

/// 接触点集合の円錐の判定が読む接線の乗数の合力。成分ごとの和である。
impl Add for 接線のラグランジュ乗数 {
    type Output = Self;
    fn add(self, 右辺: Self) -> Self {
        Self {
            x成分: self.x成分 + 右辺.x成分,
            y成分: self.y成分 + 右辺.y成分,
            z成分: self.z成分 + 右辺.z成分,
        }
    }
}
