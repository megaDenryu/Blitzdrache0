const 底面の半分の長さ: f32 = 0.5;
const 滑らせる長さ: f32 = 0.01;
pub(super) const 四隅の数: usize = 4;

// 底面の四隅の錨を持つ4行を積んだ連立。順に並べないときは四隅の順を反転する。
pub(super) fn 四隅を積んだ連立(順に並べるか: bool) -> 接触点集合の静止摩擦の連立 {
    平行移動して四隅を積んだ連立(順に並べるか, 変位::零())
}

// 場面ごと世界の中で平行移動した四隅の連立。世界位置の大きさが解に漏れていないかを見る試験が読む。
pub(super) fn 平行移動して四隅を積んだ連立(
    順に並べるか: bool, 平行移動: 変位<ワールド>
) -> 接触点集合の静止摩擦の連立 {
    let 重心 = 世界の位置を作る(0.0, 0.0, 0.0).変位を足す(平行移動);
    let 参加者 = 動的な参加者を作る(配置::生成する(重心, 姿勢::恒等()), 1.0, 1.0);
    let 四隅: [変位<ローカル>; 四隅の数] = [
        局所の変位を作る(底面の半分の長さ, 0.0, 底面の半分の長さ),
        局所の変位を作る(底面の半分の長さ, 0.0, -底面の半分の長さ),
        局所の変位を作る(-底面の半分の長さ, 0.0, 底面の半分の長さ),
        局所の変位を作る(-底面の半分の長さ, 0.0, -底面の半分の長さ),
    ];
    let mut 連立 = 接触点集合の静止摩擦の連立::点の数から空で始める(四隅の数);
    for 点の番号 in 0..四隅の数 {
        let 添字 = if 順に並べるか {
            点の番号
        } else {
            四隅の数 - 1 - 点の番号
        };
        一つの隅の行を積む(&mut 連立, 点の番号, 参加者, 四隅[添字], 平行移動);
    }
    連立
}

// 四隅を1つの連立として解いた、剛体へ適用する補正の合計と、円錐の判定が読む接線の乗数の合力。
pub(super) fn 四隅を解いた補正の合計と乗数の合力(
    順に並べるか: bool,
) -> (姿勢自由度の補正, 接線のラグランジュ乗数) {
    let 連立 = 四隅を積んだ連立(順に並べるか);
    let 同時解 = 連立.同時に解く();
    let mut 補正の合計 = 姿勢自由度の補正::零();
    let mut 合力 = 接線のラグランジュ乗数::零();
    for 番号 in 0..四隅の数 {
        let Some(一行) = 連立.一行を読む(番号) else {
            panic!("四隅の{番号}番目の行が連立に無い");
        };
        let 増分 = 同時解.一点の乗数の増分(番号);
        補正の合計 = 補正の合計.合わせる(&一行.乗数の増分を第1の参加者の補正へ分配する(増分));
        合力 = 合力 + 一行.乗数の増分を足した接線の乗数(増分);
    }
    (補正の合計, 合力)
}

fn 一つの隅の行を積む(
    連立: &mut 接触点集合の静止摩擦の連立,
    点の番号: usize,
    参加者: 姿勢自由度の参加者,
    隅: 変位<ローカル>,
    平行移動: 変位<ワールド>,
) {
    let 錨a = 接触の射影に参加する点::剛体の局所点から生成する(参加者, 隅);
    let 錨b = 接触の射影に参加する点::静的世界の固定点から生成する(
        位置::生成する(
            メートル::生成する(隅.x().値() - 滑らせる長さ),
            メートル::生成する(0.0),
            メートル::生成する(隅.z().値()),
        )
        .変位を足す(平行移動),
    );
    let 結果 = 静止摩擦の一細分の解の状態::細分の開始の状態().連立へ一行を積む(点の番号, 連立, 錨a, 錨b, 下向きの接触法線());
    assert_eq!(結果, 静止摩擦の連立へ点を入れた結果::一行を積んだ, "四隅の錨から行が積まれていない");
}
