//! 接線の同時解法の試験が共有する材料(判断13)。担当するのは、底面の四隅に錨を持つ剛体と、その四隅からx軸へ
//! 同じ長さだけ滑らせた静的世界の錨から4行を積んだ連立を作り、その連立を解いた補正と乗数の合力を返すことである。
//! 試験の本体から分けているのは、行の並びを反転して解き直す試験と、全部の点に乗数が載る試験の2つが同じ材料を
//! 読むためである。腕を四隅に置くのは、面と面の接触の連立が階数の足りない形になるのを再現するためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

