//! 接触点集合の静止摩擦を同時に解く連立の1行(判断13)。接触点1つが持つ2つの錨・その錨を結ぶ接線の向き・
//! 錨からの接線変位の長さ・その細分に積んだ接線の乗数を束ね、連立が要る量(右辺・交差の有効逆質量)と、
//! 求めた増分から作る補正と進めた乗数をこの型のメソッドで返す。
//! 法線の行(`非貫通の接触点集合の一行`)と別の型にしているのは、拘束の方向が点ごとに違うためである。法線は
//! 集合の全部の点が同じ接触法線を持つのに対し、接線の向きは各点の錨の変位から反復ごとに決まる。名前だけ
//! 一般化して1つの型を使い回すと、行の方向がどちらの意味なのか呼び出し側から読めなくなる。
//! 既存の接線の乗数をこの型が持つのは、進めた乗数がワールドの3成分の足し算 λ_t + Δs t であり、Δs だけでは
//! 決まらないためである。行が持つ向きへの増分を足す契約は `manifold_solve_tests` が固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::{メートル, ワールド, 方向, 符号付き逆キログラム};

use super::super::contact_projection_participant::接触の射影に参加する点;
use super::tangential_multiplier::接線のラグランジュ乗数;
use crate::rigid_xpbd::姿勢自由度の補正;
use crate::xpbd::ラグランジュ乗数;

/// 接触点集合の静止摩擦の連立の1行。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 静止摩擦の接触点集合の一行 {
    第1の錨: 接触の射影に参加する点,
    第2の錨: 接触の射影に参加する点,
    接線の向き: 方向<ワールド>,
    接線変位の長さ: メートル,
    既存の接線の乗数: 接線のラグランジュ乗数,
}

impl 静止摩擦の接触点集合の一行 {
    /// 錨の接線変位からこの反復の1行を作る。接線の向きは第2の錨から第1の錨へ向かう単位方向である。
    /// 前提: 接線変位の長さは正である(零の点は連立へ入れず、既存の接線の乗数を保つ)。
    pub fn 錨と接線変位から生成する(
        第1の錨: 接触の射影に参加する点,
        第2の錨: 接触の射影に参加する点,
        接線の向き: 方向<ワールド>,
        接線変位の長さ: メートル,
        既存の接線の乗数: 接線のラグランジュ乗数,
    ) -> Self {
        Self {
            第1の錨,
            第2の錨,
            接線の向き,
            接線変位の長さ,
            既存の接線の乗数,
        }
    }

    /// この反復でこの行が拘束する接線の向き t。進めた乗数はこの向きへ増分を足した値である。
    pub fn 接線の向き(&self) -> 方向<ワールド> {
        self.接線の向き
    }

    /// 連立の右辺 −C_t。接線変位を零へ戻す向きであるため負である。
    pub fn 連立の右辺(&self) -> メートル {
        self.接線変位の長さ * -1.0
    }

    /// この行と相手の行が2つの参加者を通して結び付く有効逆質量 W_ij。同じ行を2度渡せば対角の成分になる。
    pub fn 有効逆質量の交差の寄与(&self, 相手: &Self) -> 符号付き逆キログラム {
        self.第1の錨
            .二つの点の一般化逆質量の交差の寄与(self.接線の向き, &相手.第1の錨, 相手.接線の向き)
            + self
                .第2の錨
                .二つの点の一般化逆質量の交差の寄与(self.接線の向き, &相手.第2の錨, 相手.接線の向き)
    }

    /// 乗数の増分を第1の参加者の補正へ分配する。呼び出し側は集合の全部の行の補正を合計してから1度だけ適用する。
    pub fn 乗数の増分を第1の参加者の補正へ分配する(&self, 乗数の増分: ラグランジュ乗数) -> 姿勢自由度の補正 {
        self.第1の錨.乗数を補正へ分配する(self.接線の向き, 乗数の増分)
    }

    /// 乗数の増分を第2の参加者の補正へ分配する。静的世界の接触相手は動かせないため零の補正が返る。
    pub fn 乗数の増分を第2の参加者の補正へ分配する(&self, 乗数の増分: ラグランジュ乗数) -> 姿勢自由度の補正 {
        self.第2の錨.乗数を補正へ分配する(self.接線の向き.逆を向く方向(), 乗数の増分)
    }

    /// この行の右辺が持つ丸めの大きさ Σ_k |t_k| (ulp(a_A,k) + ulp(a_B,k))。右辺は2つの錨の世界位置の差を行の
    /// 向きへ射影した長さであるため、丸めは行の向きの成分ごとに座標の表現の刻みで決まる。座標の絶対値の最大で
    /// 代表させてはならない。接触と無関係な軸の座標まで最大へ入り、原点から遠いだけで解ける向きが捨てられる。
    pub fn 右辺の丸めの大きさ(&self) -> メートル {
        self.第1の錨.二つの点の世界位置の差を向きへ射影した丸めの大きさ(&self.第2の錨, self.接線の向き)
    }

    /// 増分をこの行の向きへ足した接線の乗数 λ_t + Δs t。円錐の判定はこの値の合力で行う。
    pub fn 乗数の増分を足した接線の乗数(&self, 乗数の増分: ラグランジュ乗数) -> 接線のラグランジュ乗数 {
        self.既存の接線の乗数.向きへの増分を足す(self.接線の向き, 乗数の増分)
    }
}
