//! 同じ4点の場面を世界の中で平行移動しても連立の解が変わらないことの検査(判断13)。担当するのは、法線と接線の
//! どちらにも直交する軸へ100万メートル動かしたときに、点ごとの乗数の増分が原点の付近と一致することを固定することである。
//! この軸は接線の解ける固有の向きと無関係であり、そこを動かして解が変わるなら、捨てる向きの判定が行の方向でなく
//! 世界位置の座標の大きさそのものを読んでいる。
//! 法線の軸へ動かした場合は`normal_axis_translation_tests`が別に固定する。あちらは法線の刻みが粗くなる場面であり、
//! 解が一致することではなく乗数が増え続けないことを見るためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 変位};

use super::manifold_fixture::{四隅の数, 平行移動して四隅を積んだ連立};

const 遠くまでの長さ: f32 = 1.0e6;

fn 世界の変位(x: f32, y: f32, z: f32) -> 変位<ワールド> {
    変位::成分から生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

// 平行移動した四隅の連立を解いた、点ごとの乗数の増分。
fn 平行移動して解いた乗数の増分(平行移動: 変位<ワールド>) -> [f32; 四隅の数] {
    let 同時解 = 平行移動して四隅を積んだ連立(true, 平行移動).同時に解く();
    let mut 増分 = [0.0; 四隅の数];
    for (番号, 値) in 増分.iter_mut().enumerate() {
        *値 = 同時解.一点の乗数の増分(番号).値();
    }
    増分
}

#[test]
fn 法線と接線に直交する軸へ遠くまで平行移動しても乗数の増分が変わらない() {
    // 材料の法線はy軸、接線変位はx軸である。z軸はそのどちらにも直交し、動かしても解ける向きの精度は変わらない。
    let 原点の付近 = 平行移動して解いた乗数の増分(世界の変位(0.0, 0.0, 0.0));
    let 遠く = 平行移動して解いた乗数の増分(世界の変位(0.0, 0.0, 遠くまでの長さ));
    for 番号 in 0..四隅の数 {
        assert!(原点の付近[番号].abs() > 0.0, "原点の付近で{番号}番目に乗数の増分が載っていない");
        let 差の比 = (遠く[番号] - 原点の付近[番号]).abs() / 原点の付近[番号].abs();
        assert!(
            差の比 < 1.0e-3,
            "直交する軸へ{遠くまでの長さ}メートル動かすと{番号}番目の増分が{}から{}へ変わった",
            原点の付近[番号],
            遠く[番号]
        );
    }
}
