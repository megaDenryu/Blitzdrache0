//! 接触点1つを仮に射影した後の接線の乗数の扱い(判断13)。接触点集合の円錐の判定へ足す値と、判定の結果に依らず
//! 零へ解放する点とを、この列挙が区別する。
//! 区別が要るのは、ある反復で法線と接線の乗数を得た点が、後の非貫通の反復で法線の乗数を0へ解放されるためである。
//! その点の前の接線の乗数を仮の値として残すと、実在しない法線反力の接線が合力 ‖Σλ_t‖ だけを増やし、円錐の半径
//! μ_s Σλ_n は増やさない。集合の全体が誤って滑走中へ落ちる向きの誤りであり、判断12の乗数の解放を入れて初めて
//! 通るようになった状態遷移である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::manifold_row::静止摩擦の接触点集合の一行;
use super::manifold_row_result::静止摩擦の連立へ点を入れた結果;
use super::result::静止摩擦の一回の仮の射影の結果;
use super::substep_state::静止摩擦の一細分の解の状態;
use super::tangential_multiplier::接線のラグランジュ乗数;
use crate::xpbd::ラグランジュ乗数;

/// 接触1点が接触点集合の判定へ渡す仮の接線の乗数。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 接触点の仮の接線の乗数 {
    /// 集合が円錐の内側なら確定し、超えたら仮の補正ごと捨てる値。
    集合が円錐の内側なら確定する(接線のラグランジュ乗数),
    /// 法線反力が無い点であり、集合の判定に依らず零へ解放する。
    法線反力が無いため零へ解放する,
}

impl 接触点の仮の接線の乗数 {
    /// 仮の射影の結果と、その接触点のいまの解の状態から決める。補正を求めなかった点は前の反復の乗数を保つが、
    /// 法線反力が無い点だけは保たない(その乗数を支える法線反力がもう無いためである)。
    pub fn 射影の結果と解の状態から決める(
        結果: 静止摩擦の一回の仮の射影の結果, 解の状態: 静止摩擦の一細分の解の状態
    ) -> Self {
        match 結果 {
            静止摩擦の一回の仮の射影の結果::接線を戻す補正を求めた {
                進めた接線の乗数, ..
            } => Self::集合が円錐の内側なら確定する(進めた接線の乗数),
            静止摩擦の一回の仮の射影の結果::法線反力が無い => Self::法線反力が無いため零へ解放する,
            静止摩擦の一回の仮の射影の結果::既にこの細分で滑走中
            | 静止摩擦の一回の仮の射影の結果::接線変位が零
            | 静止摩擦の一回の仮の射影の結果::両方が動かせない => {
                Self::集合が円錐の内側なら確定する(解の状態.接線のラグランジュ乗数())
            }
        }
    }

    /// 接触点集合の接線を同時に解いた後に、その点の枝と積んだ行と乗数の増分から決める。連立へ入らなかった点は
    /// 前の反復の乗数を保つが、法線反力が無い点だけは保たない(その乗数を支える法線反力がもう無いためである)。
    pub fn 積んだ行と乗数の増分から決める(
        結果: 静止摩擦の連立へ点を入れた結果,
        解の状態: 静止摩擦の一細分の解の状態,
        積んだ行: Option<静止摩擦の接触点集合の一行>,
        乗数の増分: ラグランジュ乗数,
    ) -> Self {
        match 結果 {
            静止摩擦の連立へ点を入れた結果::一行を積んだ => Self::集合が円錐の内側なら確定する(
                積んだ行.map_or_else(|| 解の状態.接線のラグランジュ乗数(), |一行| 一行.乗数の増分を足した接線の乗数(乗数の増分)),
            ),
            静止摩擦の連立へ点を入れた結果::法線反力が無い => Self::法線反力が無いため零へ解放する,
            静止摩擦の連立へ点を入れた結果::既にこの細分で滑走中
            | 静止摩擦の連立へ点を入れた結果::接線変位が零
            | 静止摩擦の連立へ点を入れた結果::両方が動かせない => {
                Self::集合が円錐の内側なら確定する(解の状態.接線のラグランジュ乗数())
            }
        }
    }

    /// 円錐の判定の合力 Σλ_t へ足す値であり、集合が内側と決まったときに確定する値でもある。解放する点は零である。
    pub fn 確定する接線の乗数(&self) -> 接線のラグランジュ乗数 {
        match self {
            Self::集合が円錐の内側なら確定する(乗数) => *乗数,
            Self::法線反力が無いため零へ解放する => 接線のラグランジュ乗数::零(),
        }
    }

    /// 集合が円錐を超えても零へ確定させる点か。捨てるのは仮の補正であって、有効集合から外れた点の解放ではない。
    pub fn 集合が円錐を超えても解放するか(&self) -> bool {
        matches!(self, Self::法線反力が無いため零へ解放する)
    }
}
