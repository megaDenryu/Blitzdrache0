//! 接触点集合1つの静止摩擦のクーロン円錐の判定(判断13)。集合の全部の点の仮の乗数を集計し、接線の乗数の合力の
//! 大きさを、法線の乗数の合計から作った円錐の半径と1度だけ比べる。
//! 点ごとに判定しないのは、面と面の接触で法線の乗数が点へ分かれる一方、各点の静止摩擦は物体全体の滑りを1点で
//! 戻そうとするためである。点ごとの判定は円錐が点の数だけ厳しくなり、傾きの正接が静止摩擦係数より小さい坂でも滑る。
//! 合力で判定するため、ここが制限するのは並進のクーロン円錐だけである。ねじりの摩擦は別の上限として後で足す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::super::contact_property::接触物性;
use super::tangential_multiplier::接線のラグランジュ乗数;
use crate::xpbd::ラグランジュ乗数;

/// 接触点集合1つの仮の乗数の集計。円錐の判定はこの2つの合計だけで決まる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触点集合の静止摩擦の仮の集計 {
    法線の乗数の合計: ラグランジュ乗数,
    接線の乗数の合計: 接線のラグランジュ乗数,
}

impl 接触点集合の静止摩擦の仮の集計 {
    /// 1点も足していない集計。接触点集合の走査の開始の値である。
    pub fn 空() -> Self {
        Self {
            法線の乗数の合計: ラグランジュ乗数::零(),
            接線の乗数の合計: 接線のラグランジュ乗数::零(),
        }
    }

    /// 接触点1つの法線の乗数と、仮に進めた接線の乗数を足した集計。
    pub fn 一点の仮の乗数を足した集計(
        &self, 法線の乗数: ラグランジュ乗数, 仮の接線の乗数: 接線のラグランジュ乗数
    ) -> Self {
        Self {
            法線の乗数の合計: self.法線の乗数の合計 + 法線の乗数,
            接線の乗数の合計: self.接線の乗数の合計 + 仮の接線の乗数,
        }
    }

    /// 接線の乗数の合力がクーロン円錐の内側に留まっているか。偽なら接触点集合の全部の点が滑走へ移る。
    pub fn 円錐の内側か(&self, 接触物性: 接触物性) -> bool {
        self.接線の乗数の合計.大きさ() <= 接触物性.静止摩擦の円錐の半径を求める(self.法線の乗数の合計)
    }
}
