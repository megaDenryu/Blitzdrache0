//! 静止摩擦の錨: 接触が始まった細分で保存した両参加者の接触点(判断13)。静止摩擦はここからの接線変位を零へ戻し、
//! クーロン円錐を超えた細分でこの点を現在の接触点へ置き直す。
//! 第2の参加者から見た点の型が幻影でなく本物の型引数なのは、剛体なら重心局所の変位、静的世界の接触相手ならワールドの
//! 位置であり、値の意味そのものが違うためである。第1の参加者は必ず剛体であるため重心局所の変位で固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::{ローカル, ワールド, 位置, 変位};

/// 接触1点が保存する両参加者の錨。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 静止摩擦の錨<第2の参加者から見た点> {
    第1の参加者の重心局所点: 変位<ローカル>,
    第2の参加者から見た点: 第2の参加者から見た点,
}

impl<第2の参加者から見た点: Copy> 静止摩擦の錨<第2の参加者から見た点> {
    /// 接触が始まった細分の接触点、または円錐を超えて置き直す細分の接触点から作る。
    pub fn 生成する(
        第1の参加者の重心局所点: 変位<ローカル>, 第2の参加者から見た点: 第2の参加者から見た点
    ) -> Self {
        Self {
            第1の参加者の重心局所点,
            第2の参加者から見た点,
        }
    }

    /// 第1の参加者(必ず剛体)の重心局所座標で表した錨。
    pub fn 第1の参加者の重心局所点(&self) -> 変位<ローカル> {
        self.第1の参加者の重心局所点
    }

    /// 第2の参加者から見た錨。剛体なら重心局所の変位、静的世界の接触相手ならワールドの位置である。
    pub fn 第2の参加者から見た点(&self) -> 第2の参加者から見た点 {
        self.第2の参加者から見た点
    }
}

/// 剛体と剛体の接触が保存する錨。どちらの側も重心局所の変位である。
pub type 剛体どうしの静止摩擦の錨 = 静止摩擦の錨<変位<ローカル>>;

/// 剛体と静的世界の接触が保存する錨。静的世界の側は細分を跨いで動かないワールドの位置である。
pub type 剛体と静的世界の静止摩擦の錨 = 静止摩擦の錨<位置<ワールド>>;
