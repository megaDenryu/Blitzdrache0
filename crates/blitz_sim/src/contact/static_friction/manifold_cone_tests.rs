//! 接触点集合の単位のクーロン円錐の判定の試験(判断13)。担当するのは3つの性質を固定することである。
//! 集合の合力が半径の内側なら内側と判定すること、超えたら超えたと判定すること、そして同じ法線の荷重と同じ接線の
//! 滑りを4点へ分けても判定が1点のときと変わらないことである。3つ目が、点ごとの判定では円錐が点の数だけ厳しく
//! なるという欠陥を踏む検査である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use blitz_math::{ワールド, 方向};

use super::manifold_cone::接触点集合の静止摩擦の仮の集計;
use super::projection_fixture::{法線の乗数, 試験の接触物性, 静止摩擦係数の値};
use super::tangential_multiplier::接線のラグランジュ乗数;
use crate::xpbd::ラグランジュ乗数;

// x軸の向きへ指定の大きさを持つ接線の乗数。
fn x軸向きの接線の乗数(大きさ: f32) -> 接線のラグランジュ乗数 {
    let 向き: 方向<ワールド> = 方向::生成する(1.0, 0.0, 0.0).unwrap();
    接線のラグランジュ乗数::零().向きへの増分を足す(向き, 法線の乗数(大きさ))
}

// 法線の荷重と接線の滑りを指定の点数へ等分した集計。
fn 等分した集計(点の数: usize, 法線の荷重: f32, 接線の合力: f32) -> 接触点集合の静止摩擦の仮の集計 {
    let 割る数 = f32::from(u8::try_from(点の数).unwrap());
    (0..点の数).fold(接触点集合の静止摩擦の仮の集計::空(), |集計, _| {
        集計.一点の仮の乗数を足した集計(法線の乗数(法線の荷重 / 割る数), x軸向きの接線の乗数(接線の合力 / 割る数))
    })
}

#[test]
fn 合力が半径の内側なら内側と判定する() {
    let 集計 = 等分した集計(1, 1.0, 0.5 * 静止摩擦係数の値);
    assert!(集計.円錐の内側か(試験の接触物性()));
}

#[test]
fn 合力が半径を超えたら超えたと判定する() {
    let 集計 = 等分した集計(1, 1.0, 2.0 * 静止摩擦係数の値);
    assert!(!集計.円錐の内側か(試験の接触物性()));
}

#[test]
fn 同じ荷重と同じ滑りを四点へ分けても判定は一点のときと変わらない() {
    for 接線の合力 in [0.5 * 静止摩擦係数の値, 2.0 * 静止摩擦係数の値] {
        let 一点 = 等分した集計(1, 1.0, 接線の合力);
        let 四点 = 等分した集計(4, 1.0, 接線の合力);
        assert_eq!(
            四点.円錐の内側か(試験の接触物性()),
            一点.円錐の内側か(試験の接触物性()),
            "接線の合力{接線の合力}で点の数によって判定が変わった"
        );
    }
}

#[test]
fn 一点も足していない集計は円錐の内側である() {
    let 空 = 接触点集合の静止摩擦の仮の集計::空();
    assert!(空.円錐の内側か(試験の接触物性()));
    assert_eq!(x軸向きの接線の乗数(0.0).大きさ(), ラグランジュ乗数::零());
}
