//! 接線の残差の持ち越し: 接触点1つが細分の境目をまたいで持つ2つの残差の組(判断24)。前の細分から持ち込んだ値と、
//! この細分の終わりに測った値である。接触拘束はこの1つの値として持ち、2つの欄を並べて持たない。
//! 2つを同じ型に束ねるのは、片方だけが在る状態(持ち込んだが測っていない・測ったが持ち込んでいない)の意味が
//! 「差が無い」の1つに畳まれ、その判定をこの型の中で閉じられるためである。
//! 破棄は持ち込んだ側にだけ効く。細分の終わりに測る値は次の細分のためのものであり、破棄の条件は
//! 「この細分の差を取ってよいか」を決めるからである(判断24の破棄条件)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

use blitz_math::{ワールド, 変位};

use super::carried_residual::持ち越す接線の残差;

/// 接触点1つの、細分の境目をまたぐ接線の残差の組。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接線の残差の持ち越し {
    前の細分から持ち込んだ残差: 持ち越す接線の残差,
    細分の終わりに測った残差: 持ち越す接線の残差,
}

impl 接線の残差の持ち越し {
    /// 何も持ち込んでいない状態。接触が始まった細分の接触拘束はここから始まる。
    pub fn 持ち込みが無い状態() -> Self {
        Self {
            前の細分から持ち込んだ残差: 持ち越す接線の残差::無し,
            細分の終わりに測った残差: 持ち越す接線の残差::無し,
        }
    }

    /// 履歴の併走が継続と判定した接触点へ、前の細分の残差を持ち込んだ状態。
    pub fn 前の細分から持ち込んだ状態(&self, 持ち込む残差: 持ち越す接線の残差) -> Self {
        Self {
            前の細分から持ち込んだ残差: 持ち込む残差,
            ..*self
        }
    }

    /// 持ち込んだ残差を破棄した状態(判断24の破棄条件)。錨を置き直した細分と、接線の乗数を零へ解放した細分が
    /// この状態へ移る。破棄した細分の速度の再構成は判断9の従来の式に一致する。
    pub fn 持ち込みを破棄した状態(&self) -> Self {
        Self {
            前の細分から持ち込んだ残差: 持ち越す接線の残差::無し,
            ..*self
        }
    }

    /// この細分の終わりに測った残差を書いた状態。次の細分の履歴へこの値が渡る。
    pub fn 細分の終わりに測った状態(&self, 測った残差: 持ち越す接線の残差) -> Self {
        Self {
            細分の終わりに測った残差: 測った残差,
            ..*self
        }
    }

    /// 速度の再構成から除く量 s_{n+1} − s_n。持ち込みが無いか、この細分に残差が無ければ差は無い。
    pub fn 細分のあいだの残差の変化(&self) -> Option<変位<ワールド>> {
        持ち越す接線の残差::細分のあいだの変化(self.前の細分から持ち込んだ残差, self.細分の終わりに測った残差)
    }

    /// 履歴へ書き戻す値。細分の終わりに測った残差そのものであり、持ち込んだ値との和ではない。
    pub fn 履歴へ書き戻す残差(&self) -> 持ち越す接線の残差 {
        self.細分の終わりに測った残差
    }
}
