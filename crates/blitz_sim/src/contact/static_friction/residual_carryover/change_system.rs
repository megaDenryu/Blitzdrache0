//! 残差の変化を打ち消す仮の補正を求める連立(判断24)。行は接触点1つにつき1つであり、右辺はその点の残差が
//! この細分で動いた長さ −|s_{n+1} − s_n| である。接線の行だけで組むため片側の条件が無く、有効集合の走査を持たない。
//! 求解は静止摩擦の連立と同じ擬似逆であり、行列は同じ `J_i M⁻¹ J_jᵀ` である。写す道具を解法と同じにするのは、
//! 除きたい量が「その変位を閉じていたら剛体がどう動いていたか」であり、それを決めるのが解法の分配そのものだからである。
//! **この連立が返す補正を配置へ適用してはならない。** 適用すると、閉じないと決めた変位を配置の側で閉じたことになり、
//! 乗数を積まずに拘束を満たす経路ができる。読むのは速度の再構成だけである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

use blitz_collision::contact_set::接触点の上限;
use blitz_math::{ワールド, 変位};

use crate::contact::contact_projection_row::一行の二つの符号付き勾配;
use crate::contact::contact_projection_row::接触の射影に参加する点;
use crate::contact::symmetric_system::{対称な連立の固有分解, 法線と接線の連立の行の上限};
use crate::rigid_xpbd::姿勢自由度の補正;
use crate::xpbd::ラグランジュ乗数;

/// 接触点集合1つぶんの、残差の変化を打ち消す仮の補正を求める連立。
pub struct 残差の変化を打ち消す仮の補正の連立 {
    行ごとの勾配: [Option<一行の二つの符号付き勾配>; 接触点の上限],
    行ごとの右辺: [f32; 法線と接線の連立の行の上限],
    行の数: usize,
}

impl 残差の変化を打ち消す仮の補正の連立 {
    /// 1行も積んでいない連立。
    pub fn 空で始める() -> Self {
        Self {
            行ごとの勾配: [None; 接触点の上限],
            行ごとの右辺: [0.0; 法線と接線の連立の行の上限],
            行の数: 0,
        }
    }

    /// 接触点1つの残差の変化を1行として積む。変化の向きが取れない(長さが零の)点は積まない。
    /// 錨の2つの参加点は、その細分が確定した配置から作ったものを渡す。
    pub fn 残差の変化を一行として積む(
        &mut self,
        第1の錨: 接触の射影に参加する点,
        第2の錨: 接触の射影に参加する点,
        残差の変化: 変位<ワールド>,
    ) {
        let Ok(向き) = 残差の変化.単位方向() else {
            return;
        };
        if 第1の錨.動かせないか() && 第2の錨.動かせないか() {
            return;
        }
        self.行ごとの勾配[self.行の数] = Some(一行の二つの符号付き勾配::接線の行として生成する(
            第1の錨, 第2の錨, 向き,
        ));
        self.行ごとの右辺[self.行の数] = -残差の変化.長さ().値();
        self.行の数 += 1;
    }

    /// 積んだ行を擬似逆で解き、2つの参加者それぞれへ配った仮の補正の合計を返す。行が無ければ零の補正である。
    /// 零の補正のときの速度の再構成は判断9の従来の式と1ビットも変わらない。
    pub fn 二つの参加者への仮の補正を求める(&self) -> (姿勢自由度の補正, 姿勢自由度の補正) {
        if self.行の数 == 0 {
            return (姿勢自由度の補正::零(), 姿勢自由度の補正::零());
        }
        let 解 = 対称な連立の固有分解::分解する(&self.対称行列を組む(), self.行の数)
            .擬似逆で解く(&self.行ごとの右辺, &self.行ごとの解けたと見なす許容差を組む());
        let (mut 第1, mut 第2) = (姿勢自由度の補正::零(), 姿勢自由度の補正::零());
        for (k, 勾配) in self.行ごとの勾配.iter().enumerate().take(self.行の数) {
            let Some(勾配) = 勾配 else { continue };
            let 増分 = ラグランジュ乗数::有効逆質量で割った長さから生成する(解.増分()[k]);
            第1 = 第1.合わせる(&勾配.乗数の増分を第1の参加者の補正へ分配する(増分));
            第2 = 第2.合わせる(&勾配.乗数の増分を第2の参加者の補正へ分配する(増分));
        }
        (第1, 第2)
    }

    // 行どうしの交差の寄与で組む対称行列。接線の行だけであるため対角へ足す刻み依存量は無い。
    fn 対称行列を組む(&self) -> [[f32; 法線と接線の連立の行の上限]; 法線と接線の連立の行の上限] {
        let mut 対称行列 = [[0.0; 法線と接線の連立の行の上限]; 法線と接線の連立の行の上限];
        for (k, 自分) in self.行ごとの勾配.iter().enumerate().take(self.行の数) {
            let Some(自分) = 自分 else { continue };
            for (l, 相手) in self.行ごとの勾配.iter().enumerate().take(self.行の数) {
                if let Some(相手) = 相手 {
                    対称行列[k][l] = 自分.交差の寄与(相手).値();
                }
            }
        }
        対称行列
    }

    // 行ごとの解けたと見なす許容差。静止摩擦の行と同じ式であり、刻みを下回る変化は捨てる。
    fn 行ごとの解けたと見なす許容差を組む(&self) -> [f32; 法線と接線の連立の行の上限] {
        let mut 許容差 = [0.0; 法線と接線の連立の行の上限];
        for (k, 勾配) in self.行ごとの勾配.iter().enumerate().take(self.行の数) {
            if let Some(勾配) = 勾配 {
                許容差[k] = 勾配.解けたと見なす許容差().値();
            }
        }
        許容差
    }
}
