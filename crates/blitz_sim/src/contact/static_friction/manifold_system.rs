//! 接触点集合1つの接線の連立(判断13)。連立へ入る点の行を集め、W_t Δs = −C_t を1度に解く。
//! 法線の連立と違って有効集合の組み替えを持たない。法線の乗数が正の点だけを対象にした両側拘束として扱うため
//! である(接線の乗数に片側性は無く、円錐の判定は集合の合力で1度だけ行う)。法線の乗数が零の点と接線変位が零の
//! 点は行を作らず、この連立へ入らない。
//! 解くのは `contact/symmetric_system` の擬似逆であり、法線の連立が読む正則化つきの LDLᵀ ではない。接線の右辺は
//! 点ごとの錨の変位の長さであり、剛体1つの運動では実現できない成分を必ず含む。正則化で解くとその成分が
//! 正則化で割られて乗数だけが桁で膨れ、クーロン円錐の判定が壊れる(理由の全文は擬似逆の側に書いた)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_collision::contact_set::接触点の上限;

use super::super::symmetric_system::対称な連立の固有分解;
use super::manifold_row::静止摩擦の接触点集合の一行;
use super::manifold_solution::接触点集合の静止摩擦の同時解;
use crate::xpbd::ラグランジュ乗数;

/// 接触点集合1つの接線の連立。行を持つ点と持たない点が混ざるため、点の番号で引ける受け皿に積む。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触点集合の静止摩擦の連立 {
    点ごとの行: [Option<静止摩擦の接触点集合の一行>; 接触点の上限],
    点の数: usize,
}

impl 接触点集合の静止摩擦の連立 {
    /// 1行も積んでいない連立。
    /// 注意: 点の数が接触点の上限を超える集合は衝突数学層の不変条件の破れであり、添字の範囲外として落ちる。
    pub fn 点の数から空で始める(点の数: usize) -> Self {
        Self {
            点ごとの行: [None; 接触点の上限],
            点の数,
        }
    }

    /// 連立へ入る点の行を積む。
    pub fn 一行を積む(&mut self, 点の番号: usize, 一行: 静止摩擦の接触点集合の一行) {
        self.点ごとの行[点の番号] = Some(一行);
    }

    /// 積んだ行。連立へ入らなかった点は無しである。補正の分配と進めた乗数の組み立てを呼び出し側が行う。
    pub fn 一行を読む(&self, 点の番号: usize) -> Option<静止摩擦の接触点集合の一行> {
        self.点ごとの行[点の番号]
    }

    /// 積んだ行を1つの連立として解いた点ごとの乗数の増分。
    pub fn 同時に解く(&self) -> 接触点集合の静止摩擦の同時解 {
        let mut もとの点の番号 = [0usize; 接触点の上限];
        let mut 個数 = 0;
        for 番号 in 0..self.点の数 {
            if self.点ごとの行[番号].is_some() {
                もとの点の番号[個数] = 番号;
                個数 += 1;
            }
        }
        let 分解 = 対称な連立の固有分解::分解する(&self.有効逆質量行列を組む(&もとの点の番号, 個数), 個数);
        let 解 = 分解.擬似逆で解く(&self.定数項を組む(&もとの点の番号, 個数));
        let mut 乗数の増分 = [ラグランジュ乗数::零(); 接触点の上限];
        for (k, 番号) in もとの点の番号.iter().enumerate().take(個数) {
            乗数の増分[*番号] = ラグランジュ乗数::有効逆質量で割った長さから生成する(解[k]);
        }
        接触点集合の静止摩擦の同時解::乗数の増分の一覧から生成する(乗数の増分)
    }

    // 積んだ行の交差の有効逆質量 W_t。正則化は足さない(擬似逆が小さい固有値の向きを捨てる)。
    fn 有効逆質量行列を組む(
        &self, もとの点の番号: &[usize; 接触点の上限], 個数: usize
    ) -> [[f32; 接触点の上限]; 接触点の上限] {
        let mut 対称行列 = [[0.0; 接触点の上限]; 接触点の上限];
        for k in 0..個数 {
            for l in 0..=k {
                let (Some(自分), Some(相手)) = (self.点ごとの行[もとの点の番号[k]], self.点ごとの行[もとの点の番号[l]])
                else {
                    continue;
                };
                let 値 = 自分.有効逆質量の交差の寄与(&相手).値();
                対称行列[k][l] = 値;
                対称行列[l][k] = 値;
            }
        }
        対称行列
    }

    // 積んだ行の右辺 −C_t を抜き出した並び。
    fn 定数項を組む(&self, もとの点の番号: &[usize; 接触点の上限], 個数: usize) -> [f32; 接触点の上限] {
        let mut 定数項 = [0.0; 接触点の上限];
        for (k, 番号) in もとの点の番号.iter().enumerate().take(個数) {
            if let Some(一行) = self.点ごとの行[*番号] {
                定数項[k] = 一行.連立の右辺().値();
            }
        }
        定数項
    }
}
