//! 接触点1つを静止摩擦の連立へ入れる工程(判断13)。錨の世界位置から接線変位を求め、その単位方向を行の方向として
//! 置き、作った行を連立へ積む。状態の定義(`substep_state`)からこの工程を分けているのは、状態が細分の開始で1度だけ
//! 作られるのに対し、この工程が細分の中の反復ごとに呼ばれるためである。
//!   Δ_t = (a_A − a_B) − ((a_A − a_B)·n) n、C_t = |Δ_t|、t = Δ_t ÷ |Δ_t|
//! 乗数の増分 Δs はこの行だけでは決まらない。集合の全部の行を W_t Δs = −C_t の連立として解いた後に決まる。
//! 点ごとに w̃_t で割って即座に補正を適用すると、1点の補正が次の点の腕と有効逆質量を変え、各点が物体全体の
//! 滑りを1点で戻そうとして接線の乗数が積み増され、円錐を超えて集合が滑走へ落ちる。
//! コンプライアンスを持たないのは、正本が静止摩擦を硬い位置拘束として書いているためである(α = 0)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::{ワールド, 方向};

use super::super::contact_projection_participant::接触の射影に参加する点;
use super::manifold_row::静止摩擦の接触点集合の一行;
use super::manifold_row_result::静止摩擦の連立へ点を入れた結果;
use super::manifold_system::接触点集合の静止摩擦の連立;
use super::substep_state::静止摩擦の一細分の解の状態;

impl 静止摩擦の一細分の解の状態 {
    /// この反復の1行を作って連立へ積む。2つの点は接触点ではなく錨であり、接触法線は第1の参加者から第2の参加者へ
    /// 向かう向きである。呼び出し側は、その細分に法線反力が在る接触点だけをここへ通す。
    pub fn 連立へ一行を積む(
        &self,
        点の番号: usize,
        連立: &mut 接触点集合の静止摩擦の連立,
        錨a: 接触の射影に参加する点,
        錨b: 接触の射影に参加する点,
        接触法線: 方向<ワールド>,
    ) -> 静止摩擦の連立へ点を入れた結果 {
        if 錨a.動かせないか() && 錨b.動かせないか() {
            return 静止摩擦の連立へ点を入れた結果::両方が動かせない;
        }
        if self.滑走中か() {
            return 静止摩擦の連立へ点を入れた結果::既にこの細分で滑走中;
        }
        let 接線変位 = (錨a.世界位置() - 錨b.世界位置()).方向の成分を除く(接触法線);
        let Ok(接線の向き) = 接線変位.単位方向() else {
            return 静止摩擦の連立へ点を入れた結果::接線変位が零;
        };
        連立.一行を積む(
            点の番号,
            静止摩擦の接触点集合の一行::錨と接線変位から生成する(
                錨a,
                錨b,
                接線の向き,
                接線変位.長さ(),
                self.接線のラグランジュ乗数(),
            ),
        );
        静止摩擦の連立へ点を入れた結果::一行を積んだ
    }
}
