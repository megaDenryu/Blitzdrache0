//! 静止摩擦の等方性の試験(判断13)。接線変位の向きを接平面の中で回しても、乗数の増分の大きさと円錐の判定が
//! 変わらないことを固定する。これが、接線2軸を独立に切り詰める箱近似を採っていないことの反証である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use std::f32::consts::PI;

use super::projection_fixture::{一回射影する, 接線変位の長さ, 法線の乗数, 静止摩擦係数の値};
use super::result::静止摩擦の一回の射影の結果;

#[test]
fn 接線変位の向きを接平面で回しても増分の大きさと円錐の判定が変わらない() {
    let 内側の乗数 = 法線の乗数(4.0 * 接線変位の長さ / 静止摩擦係数の値);
    let 外側の乗数 = 法線の乗数(0.5 * 接線変位の長さ / 静止摩擦係数の値);
    for 段 in 0u8..12 {
        let 角 = PI * f32::from(段) / 6.0;
        let 静止摩擦の一回の射影の結果::円錐の内側で保持した {
            更新後の解の状態, 補正a,
        ..
        } = 一回射影する(角, 内側の乗数)
        else {
            panic!("角{角}で円錐の内側の枝が返っていない");
        };
        assert!((補正a.並進().長さ().値() - 接線変位の長さ).abs() < 1.0e-6, "角{角}で補正の長さが変わった");
        assert!(
            (更新後の解の状態.接線のラグランジュ乗数().大きさ().値() - 接線変位の長さ).abs() < 1.0e-6,
            "角{角}で接線の乗数の大きさが変わった"
        );
        assert!(
            matches!(
                一回射影する(角, 外側の乗数),
                静止摩擦の一回の射影の結果::円錐を超えて滑走中になった { .. }
            ),
            "角{角}で円錐を超える判定が変わった"
        );
    }
}
