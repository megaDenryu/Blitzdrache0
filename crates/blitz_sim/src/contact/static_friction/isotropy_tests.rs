//! 静止摩擦の等方性の試験(判断13)。接線変位の向きを接平面の中で回しても、補正の長さと乗数の増分の大きさ、および
//! 接触点集合の円錐の判定が変わらないことを固定する。これが、接線2軸を独立に切り詰める箱近似を採っていないことの反証である。
//! 場面の単位の等方性(0度・30度・45度で滑り出す傾きの境界が変わらないこと)は`scene/slope_tests`が固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use std::f32::consts::PI;

use super::manifold_cone::接触点集合の静止摩擦の仮の集計;
use super::projection_fixture::{一回仮に射影する, 接線変位の長さ, 法線の乗数, 試験の接触物性, 静止摩擦係数の値};
use super::result::静止摩擦の一回の仮の射影の結果;

// 接触点1つだけの接触点集合として、その向きの仮の乗数で円錐を判定する。
fn 一点の集合の円錐の判定(角: f32, 法線の乗数: crate::xpbd::ラグランジュ乗数) -> bool {
    let 静止摩擦の一回の仮の射影の結果::接線を戻す補正を求めた {
        進めた接線の乗数, ..
    } = 一回仮に射影する(角)
    else {
        panic!("角{角}で補正を求めた枝が返っていない");
    };
    接触点集合の静止摩擦の仮の集計::空()
        .一点の仮の乗数を足した集計(法線の乗数, 進めた接線の乗数)
        .円錐の内側か(試験の接触物性())
}

#[test]
fn 接線変位の向きを接平面で回しても増分の大きさと円錐の判定が変わらない() {
    let 内側の乗数 = 法線の乗数(4.0 * 接線変位の長さ / 静止摩擦係数の値);
    let 外側の乗数 = 法線の乗数(0.5 * 接線変位の長さ / 静止摩擦係数の値);
    for 段 in 0u8..12 {
        let 角 = PI * f32::from(段) / 6.0;
        let 静止摩擦の一回の仮の射影の結果::接線を戻す補正を求めた {
            補正a, 進めた接線の乗数,
        ..
        } = 一回仮に射影する(角)
        else {
            panic!("角{角}で補正を求めた枝が返っていない");
        };
        assert!((補正a.並進().長さ().値() - 接線変位の長さ).abs() < 1.0e-6, "角{角}で補正の長さが変わった");
        assert!(
            (進めた接線の乗数.大きさ().値() - 接線変位の長さ).abs() < 1.0e-6,
            "角{角}で接線の乗数の大きさが変わった"
        );
        assert!(一点の集合の円錐の判定(角, 内側の乗数), "角{角}で円錐の内側の判定が変わった");
        assert!(!一点の集合の円錐の判定(角, 外側の乗数), "角{角}で円錐を超える判定が変わった");
    }
}
