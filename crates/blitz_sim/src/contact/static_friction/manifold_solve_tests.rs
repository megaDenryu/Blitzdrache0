//! 接線の同時解法の1点の振る舞いの検査(判断13)。担当するのは2つを固定することである。
//! 接触点が1つだけの集合では旧の逐次の射影と同じ乗数の増分になること、そして進めた接線の乗数が「その反復の
//! 行の向きへ増分を足した値」であることである。2つ目が要るのは、接線の乗数がワールドの3成分のベクトルであり、
//! 行の向きが反復ごとに接平面の中で回るためである。
//! 4点の並びに依らないことは`manifold_order_tests`が固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

