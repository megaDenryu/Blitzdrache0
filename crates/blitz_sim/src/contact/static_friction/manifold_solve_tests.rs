// 錨1組だけを積んだ連立と、それを解いた乗数の増分。
fn 一点の連立を解く(
    状態: 静止摩擦の一細分の解の状態,
    錨a: 接触の射影に参加する点,
    錨b: 接触の射影に参加する点,
) -> (静止摩擦の接触点集合の一行, ラグランジュ乗数) {
    let mut 連立 = 接触点集合の静止摩擦の連立::点の数から空で始める(1);
    let 結果 = 状態.連立へ一行を積む(0, &mut 連立, 錨a, 錨b, 下向きの接触法線());
    assert_eq!(結果, 静止摩擦の連立へ点を入れた結果::一行を積んだ, "錨から行が積まれていない");
    let Some(一行) = 連立.一行を読む(0) else {
        panic!("積んだはずの行が連立に無い");
    };
    (一行, 連立.同時に解く().一点の乗数の増分(0))
}

#[test]
fn 接触点が一つの集合では逐次の射影と同じ乗数の増分になる() {
    let 錨a = 重心を錨にした剛体();
    let 錨b = 接平面で回した静的世界の錨(0.0);
    let 静止摩擦の一回の仮の射影の結果::接線を戻す補正を求めた {
        進めた接線の乗数, ..
    } = 静止摩擦の一細分の解の状態::細分の開始の状態().一回仮に射影する(錨a, 錨b, 下向きの接触法線())
    else {
        panic!("逐次の射影が補正を求めた枝を返していない");
    };
    let (一行, 増分) = 一点の連立を解く(静止摩擦の一細分の解の状態::細分の開始の状態(), 錨a, 錨b);
    let 同時の大きさ = 一行.乗数の増分を足した接線の乗数(増分).大きさ().値();
    let 逐次の大きさ = 進めた接線の乗数.大きさ().値();
    assert!(逐次の大きさ > 0.0, "材料の接線変位が零である");
    assert!(
        (同時の大きさ - 逐次の大きさ).abs() / 逐次の大きさ < 1.0e-3,
        "1点の集合で同時解{同時の大きさ}が逐次の射影{逐次の大きさ}と一致しない"
    );
}

#[test]
fn 進めた接線の乗数はその反復の行の向きへ増分を足した値である() {
    let x軸: 方向<ワールド> = 方向::生成する(1.0, 0.0, 0.0).unwrap();
    let 既存の乗数 = 接線のラグランジュ乗数::零().向きへの増分を足す(x軸, ラグランジュ乗数::有効逆質量で割った長さから生成する(0.03));
    let 状態 = 静止摩擦の一細分の解の状態::細分の開始の状態().仮の乗数を確定した状態(既存の乗数);
    // z軸の向きへ滑らせた錨を渡すと、行の向きはz軸になる。x軸の既存の乗数はそのまま残る。
    let (一行, 増分) = 一点の連立を解く(状態, 重心を錨にした剛体(), 接平面で回した静的世界の錨(std::f32::consts::FRAC_PI_2));
    let 進めた = 一行.乗数の増分を足した接線の乗数(増分);
    let 期待 = 既存の乗数.向きへの増分を足す(方向::生成する(0.0, 0.0, 1.0).unwrap(), 増分);
    assert!(
        (進めた.大きさ().値() - 期待.大きさ().値()).abs() < 1.0e-6,
        "行の向きへ増分を足した値になっていない: {進めた:?} と {期待:?}"
    );
    assert!(
        (進めた.大きさ().値() - (0.03 * 0.03 + 接線変位の長さ * 接線変位の長さ).sqrt()).abs() < 1.0e-4,
        "x軸の既存の乗数とz軸の増分が直交して合成されていない: {進めた:?}"
    );
}
