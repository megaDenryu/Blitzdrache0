//! 静止摩擦を1細分のあいだ解いていく途中の状態(判断13)。接線のラグランジュ乗数と、その細分で滑走中と印されたかの2つを持つ。
//! 乗数は接触点ごとの値であり、滑走中の印は接触点集合の全部の点へ同時に立つ値である。印を集合の単位にするのは、
//! クーロン円錐の判定が集合の合力で行われ、超えたら集合の全部の点が滑走へ移るためである。
//! 滑走中の印は速度段階が読む。静止摩擦がクーロン円錐の内側で接触を保持している細分では、速度段階の動摩擦を重ねない
//! (同じ細分で位置の静止摩擦と速度の動摩擦が二重に効くことを避ける)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::tangential_multiplier::接線のラグランジュ乗数;

/// 接触1点が1細分の反復のあいだ持ち越す静止摩擦の解の状態。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 静止摩擦の一細分の解の状態 {
    接線のラグランジュ乗数: 接線のラグランジュ乗数,
    滑走中か: bool,
}

impl 静止摩擦の一細分の解の状態 {
    /// 細分の開始の状態。乗数は零で始め、まだ滑走中ではない。
    pub fn 細分の開始の状態() -> Self {
        Self {
            接線のラグランジュ乗数: 接線のラグランジュ乗数::零(),
            滑走中か: false,
        }
    }

    /// この細分で累積した接線の乗数。
    pub fn 接線のラグランジュ乗数(&self) -> 接線のラグランジュ乗数 {
        self.接線のラグランジュ乗数
    }

    /// この接触点の属する接触点集合が、この細分でクーロン円錐を超えて滑走中と印されたか。
    /// 速度段階の動摩擦がこの印の立った接触点だけへ効く。
    pub fn 滑走中か(&self) -> bool {
        self.滑走中か
    }

    // 接触点集合の判定が円錐の内側と決めた後の状態。仮に進めた乗数をそのまま確定し、滑走中の印は立てない。
    pub(in crate::contact) fn 仮の乗数を確定した状態(&self, 進めた乗数: 接線のラグランジュ乗数) -> Self {
        Self {
            接線のラグランジュ乗数: 進めた乗数,
            滑走中か: self.滑走中か,
        }
    }

    // 接触点集合が円錐を超えた後の状態。仮の補正は集合ごと捨てるため乗数は確定前のままであり、滑走中の印だけを立てる。
    pub(in crate::contact) fn 接触点集合が滑走中になった状態(&self) -> Self {
        Self {
            接線のラグランジュ乗数: self.接線のラグランジュ乗数,
            滑走中か: true,
        }
    }
}
