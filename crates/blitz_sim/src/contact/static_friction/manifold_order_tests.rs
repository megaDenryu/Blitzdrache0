//! 接線の同時解法が行の並びに依らないことの検査(判断13)。担当するのは2つを固定することである。
//! 面と面の4点の順を反転しても補正の合計と円錐の判定が読む合力が変わらないこと、そして4点のどれにも接線の
//! 乗数が載ることである。2つ目が、階数の足りない連立で荷重が一部の点へ偏らないことの検査である。
//! 1点の集合での旧の形との一致と、行の向きへ増分を足す契約は`manifold_solve_tests`が固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use super::manifold_fixture::{四隅の数, 四隅を積んだ連立, 四隅を解いた補正の合計と乗数の合力};

#[test]
fn 四点の順を反転しても補正と円錐の判定の合力が変わらない() {
    let (順の補正, 順の合力) = 四隅を解いた補正の合計と乗数の合力(true);
    let (逆の補正, 逆の合力) = 四隅を解いた補正の合計と乗数の合力(false);
    let 補正の差 = (順の補正.並進() - 逆の補正.並進()).長さ().値();
    assert!(補正の差 < 1.0e-6, "4点の順を反転すると補正が変わった: {補正の差}");
    let 合力の差 = (順の合力.大きさ().値() - 逆の合力.大きさ().値()).abs();
    assert!(合力の差 < 1.0e-6, "4点の順を反転すると円錐の判定の合力が変わった: {合力の差}");
    assert!(順の合力.大きさ().値() > 0.0, "材料の接線の乗数が零である");
}

#[test]
fn 面と面の四点でも全部の点に接線の乗数が載る() {
    let 同時解 = 四隅を積んだ連立(true).同時に解く();
    for 番号 in 0..四隅の数 {
        let 増分 = 同時解.一点の乗数の増分(番号).値();
        assert!(増分 < 0.0, "四隅の{番号}番目に接線の乗数が載っていない: {増分}");
    }
}
