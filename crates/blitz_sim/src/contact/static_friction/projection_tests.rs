//! 静止摩擦の仮の射影の枝の試験(判断13)。担当するのは3つの性質を固定することである。錨へ戻す補正と進めた接線の乗数が
//! 返ること、接触点集合が滑走中と印された後は同じ細分の反復で補正を返さないこと、接線変位が零のときに何もしないことである。
//! クーロン円錐の判定は`manifold_cone_tests`が、向きに依らないことは`isotropy_tests`が固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;
use blitz_math::位置;

use super::super::contact_projection_row::接触の射影に参加する点;
use super::projection_fixture::{
    一回仮に射影する, 下向きの接触法線, 接平面で回した静的世界の錨, 接線変位の長さ, 重心を錨にした剛体
};
use super::result::静止摩擦の一回の仮の射影の結果;
use super::substep_state::静止摩擦の一細分の解の状態;

#[test]
fn 錨へ戻す補正と進めた接線の乗数が返る() {
    // 有効逆質量1のとき増分の大きさは接線変位の長さに等しい。
    let 結果 = 一回仮に射影する(0.0);
    let 静止摩擦の一回の仮の射影の結果::接線を戻す補正を求めた {
        補正a, 進めた接線の乗数,
    ..
    } = 結果
    else {
        panic!("補正を求めた枝が返っていない: {結果:?}");
    };
    assert!((補正a.並進().長さ().値() - 接線変位の長さ).abs() < 1.0e-6);
    assert!(補正a.並進().x().値() > 0.0, "剛体が錨の側へ戻っていない");
    assert!((進めた接線の乗数.大きさ().値() - 接線変位の長さ).abs() < 1.0e-6);
}

#[test]
fn 滑走中と印された接触点集合の点は同じ細分の後の反復で補正を返さない() {
    let 滑走中の状態 = 静止摩擦の一細分の解の状態::細分の開始の状態().接触点集合が滑走中になった状態();
    assert!(滑走中の状態.滑走中か());
    let 次の反復 = 滑走中の状態.一回仮に射影する(重心を錨にした剛体(), 接平面で回した静的世界の錨(0.0), 下向きの接触法線());
    assert_eq!(次の反復, 静止摩擦の一回の仮の射影の結果::既にこの細分で滑走中);
}

#[test]
fn 錨が接触点と一致していれば接線変位が零の枝を返す() {
    let 結果 = 静止摩擦の一細分の解の状態::細分の開始の状態().一回仮に射影する(
        重心を錨にした剛体(),
        接触の射影に参加する点::静的世界の固定点から生成する(位置::生成する(
            メートル::生成する(0.0),
            メートル::生成する(0.0),
            メートル::生成する(0.0),
        )),
        下向きの接触法線(),
    );
    assert_eq!(結果, 静止摩擦の一回の仮の射影の結果::接線変位が零);
}
