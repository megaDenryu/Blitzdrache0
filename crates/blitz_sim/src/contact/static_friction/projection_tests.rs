//! 静止摩擦の射影の枝の試験(判断13)。担当するのは4つの性質を固定することである。クーロン円錐の内側で錨へ戻す
//! 補正が返ること、超えたら補正を返さず滑走中と印すこと、同じ細分で一度滑走中になった接触点が以後の反復で補正を
//! 返さないこと、接線変位が零のときに何もしないことである。等方性は`isotropy_tests`が固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;
use blitz_math::位置;

use super::super::contact_projection_participant::接触の射影に参加する点;
use super::projection_fixture::{
    一回射影する, 下向きの接触法線, 接平面で回した静的世界の錨, 接線変位の長さ, 法線の乗数, 試験の接触物性, 重心を錨にした剛体, 静止摩擦係数の値,
};
use super::result::静止摩擦の一回の射影の結果;
use super::substep_state::静止摩擦の一細分の解の状態;
use crate::xpbd::ラグランジュ乗数;

#[test]
fn 円錐の内側では錨へ戻す補正が返り接線の乗数が進む() {
    // 有効逆質量1のとき増分の大きさは接線変位の長さに等しく、円錐の半径は μ_s λ_n である。
    let 結果 = 一回射影する(0.0, 法線の乗数(4.0 * 接線変位の長さ / 静止摩擦係数の値));
    let 静止摩擦の一回の射影の結果::円錐の内側で保持した {
        補正a, 更新後の解の状態,
    ..
    } = 結果
    else {
        panic!("円錐の内側で補正が返っていない: {結果:?}");
    };
    assert!((補正a.並進().長さ().値() - 接線変位の長さ).abs() < 1.0e-6);
    assert!(補正a.並進().x().値() > 0.0, "剛体が錨の側へ戻っていない");
    assert!(!更新後の解の状態.滑走中か());
    assert!((更新後の解の状態.接線のラグランジュ乗数().大きさ().値() - 接線変位の長さ).abs() < 1.0e-6);
}

#[test]
fn 円錐を超えると補正を返さず滑走中と印す() {
    let 結果 = 一回射影する(0.0, 法線の乗数(0.5 * 接線変位の長さ / 静止摩擦係数の値));
    let 静止摩擦の一回の射影の結果::円錐を超えて滑走中になった { 更新後の解の状態 } = 結果 else {
        panic!("円錐を超えた枝が返っていない: {結果:?}");
    };
    assert!(更新後の解の状態.滑走中か());
    assert_eq!(更新後の解の状態.接線のラグランジュ乗数().大きさ(), ラグランジュ乗数::零());
}

#[test]
fn 一度滑走中になった接触点は同じ細分の後の反復で補正を返さない() {
    let 結果 = 一回射影する(0.0, 法線の乗数(0.5 * 接線変位の長さ / 静止摩擦係数の値));
    let 静止摩擦の一回の射影の結果::円錐を超えて滑走中になった { 更新後の解の状態 } = 結果 else {
        panic!("円錐を超えた枝が返っていない: {結果:?}");
    };
    let 次の反復 = 更新後の解の状態.一回射影する(
        重心を錨にした剛体(),
        接平面で回した静的世界の錨(0.0),
        下向きの接触法線(),
        試験の接触物性(),
        法線の乗数(4.0 * 接線変位の長さ / 静止摩擦係数の値),
    );
    assert_eq!(次の反復, 静止摩擦の一回の射影の結果::既にこの細分で滑走中);
}

#[test]
fn 錨が接触点と一致していれば接線変位が零の枝を返す() {
    let 結果 = 静止摩擦の一細分の解の状態::細分の開始の状態().一回射影する(
        重心を錨にした剛体(),
        接触の射影に参加する点::静的世界の固定点から生成する(位置::生成する(
            メートル::生成する(0.0),
            メートル::生成する(0.0),
            メートル::生成する(0.0),
        )),
        下向きの接触法線(),
        試験の接触物性(),
        法線の乗数(1.0),
    );
    assert_eq!(結果, 静止摩擦の一回の射影の結果::接線変位が零);
}
