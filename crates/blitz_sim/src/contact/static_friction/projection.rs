//! 静止摩擦の位置拘束の射影(判断13)。錨からの接線変位を零へ戻す1回の反復であり、クーロン円錐の内側でだけ補正を返す。
//! 状態の定義からこの工程を分けているのは、状態が細分の開始で1度だけ作られるのに対し、この射影が細分の中の反復ごとに
//! 呼ばれるためである。触れるのは接線の乗数と滑走中の印の2つだけである。
//!   Δ_t = (a_A − a_B) − ((a_A − a_B)·n) n、C = |Δ_t|、t = Δ_t ÷ |Δ_t|
//!   Δλ_t = −C ÷ (w̃_A,t + w̃_B,t)、|λ_t + Δλ_t t| ≤ μ_s λ_n なら A へ Δλ_t t、B へ −Δλ_t t の補正を分配する
//! コンプライアンスを持たないのは、正本が静止摩擦を硬い位置拘束として書いているためである(α = 0 で α̃ の項が消える)。
//! 接線2軸を独立に切り詰める箱近似を採らず、2次元の乗数の大きさ1つで円錐を判定するため、判定は等方である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::{ワールド, 方向};

use super::super::contact_projection_participant::接触の射影に参加する点;
use super::super::contact_property::接触物性;
use super::result::静止摩擦の一回の射影の結果;
use super::substep_state::静止摩擦の一細分の解の状態;
use crate::xpbd::ラグランジュ乗数;

impl 静止摩擦の一細分の解の状態 {
    /// 正典式の1回の反復。2つの点は接触点ではなく錨であり、接触法線は第1の参加者から第2の参加者へ向かう向きである。
    /// 法線のラグランジュ乗数は、その細分で非貫通が実際に押し戻した接触点のものだけを渡す。
    pub fn 一回射影する(
        &self,
        錨a: 接触の射影に参加する点,
        錨b: 接触の射影に参加する点,
        接触法線: 方向<ワールド>,
        接触物性: 接触物性,
        法線のラグランジュ乗数: ラグランジュ乗数,
    ) -> 静止摩擦の一回の射影の結果 {
        if 錨a.動かせないか() && 錨b.動かせないか() {
            return 静止摩擦の一回の射影の結果::両方が動かせない;
        }
        let 接線変位 = (錨a.世界位置() - 錨b.世界位置()).方向の成分を除く(接触法線);
        let Ok(接線の向き) = 接線変位.単位方向() else {
            return 静止摩擦の一回の射影の結果::接線変位が零;
        };
        let 有効逆質量 = 錨a.一般化逆質量(接線の向き) + 錨b.一般化逆質量(接線の向き);
        let 増分 = ラグランジュ乗数::長さを逆質量で割って生成する(接線変位.長さ() * -1.0, 有効逆質量);
        let 進めた乗数 = self.接線のラグランジュ乗数().向きへの増分を足す(接線の向き, 増分);
        if 進めた乗数.大きさ() > 接触物性.静止摩擦の円錐の半径を求める(法線のラグランジュ乗数) {
            return 静止摩擦の一回の射影の結果::円錐を超えて滑走中になった {
                更新後の解の状態: self.滑走中と印した状態(),
            };
        }
        静止摩擦の一回の射影の結果::円錐の内側で保持した {
            補正a: 錨a.乗数を補正へ分配する(接線の向き, 増分),
            補正b: 錨b.乗数を補正へ分配する(接線の向き.逆を向く方向(), 増分),
            更新後の解の状態: self.円錐の内側で乗数を進めた状態(進めた乗数),
        }
    }
}
