//! 静止摩擦の位置拘束を接触点1つへ仮に射影する工程(判断13)。錨からの接線変位を零へ戻す1回の反復である。
//! 状態の定義からこの工程を分けているのは、状態が細分の開始で1度だけ作られるのに対し、この射影が細分の中の反復ごとに
//! 呼ばれるためである。触れるのは接線の乗数と滑走中の印の2つだけである。
//!   Δ_t = (a_A − a_B) − ((a_A − a_B)·n) n、C = |Δ_t|、t = Δ_t ÷ |Δ_t|
//!   Δλ_t = −C ÷ (w̃_A,t + w̃_B,t)、A へ Δλ_t t、B へ −Δλ_t t の補正と、進めた乗数 λ_t + Δλ_t t を返す
//! クーロン円錐の判定をここで行わないのは、判定が接触点集合の単位だからである(判定は`manifold_cone`が持つ)。
//! コンプライアンスを持たないのは、正本が静止摩擦を硬い位置拘束として書いているためである(α = 0 で α̃ の項が消える)。
//! 接線2軸を独立に切り詰める箱近似を採らず、2次元の乗数の大きさ1つで円錐を判定するため、判定は等方である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::{ワールド, 方向};

use super::super::contact_projection_row::接触の射影に参加する点;
use super::result::静止摩擦の一回の仮の射影の結果;
use super::substep_state::静止摩擦の一細分の解の状態;
use crate::xpbd::ラグランジュ乗数;

impl 静止摩擦の一細分の解の状態 {
    /// 正典式の1回の反復。2つの点は接触点ではなく錨であり、接触法線は第1の参加者から第2の参加者へ向かう向きである。
    /// 呼び出し側は、その細分に法線反力が在る接触点だけをここへ通す。
    pub fn 一回仮に射影する(
        &self,
        錨a: 接触の射影に参加する点,
        錨b: 接触の射影に参加する点,
        接触法線: 方向<ワールド>,
    ) -> 静止摩擦の一回の仮の射影の結果 {
        if 錨a.動かせないか() && 錨b.動かせないか() {
            return 静止摩擦の一回の仮の射影の結果::両方が動かせない;
        }
        if self.滑走中か() {
            return 静止摩擦の一回の仮の射影の結果::既にこの細分で滑走中;
        }
        let 接線変位 = (錨a.世界位置() - 錨b.世界位置()).方向の成分を除く(接触法線);
        let Ok(接線の向き) = 接線変位.単位方向() else {
            return 静止摩擦の一回の仮の射影の結果::接線変位が零;
        };
        let 有効逆質量 = 錨a.一般化逆質量(接線の向き) + 錨b.一般化逆質量(接線の向き);
        let 増分 = ラグランジュ乗数::長さを逆質量で割って生成する(接線変位.長さ() * -1.0, 有効逆質量);
        静止摩擦の一回の仮の射影の結果::接線を戻す補正を求めた {
            補正a: 錨a.乗数を補正へ分配する(接線の向き, 増分),
            補正b: 錨b.乗数を補正へ分配する(接線の向き.逆を向く方向(), 増分),
            進めた接線の乗数: self.接線のラグランジュ乗数().向きへの増分を足す(接線の向き, 増分),
        }
    }
}
