//! 非貫通を1細分のあいだ解いていく途中の状態(判断12)。法線のラグランジュ乗数と、その細分で実際に詰めた
//! 法線方向の相対補正の長さの累計の2つを持つ。長さを乗数と別に持つのは、1細分で詰めてよい貫通の長さの上限が
//! 長さの言葉で定まるのに対し、乗数への換算 λ = 長さ ÷ w̃ が反復ごとの有効逆質量 w̃ に依存するためである。
//! w̃ は腕とワールドの逆慣性テンソルを含むため、姿勢の補正や他の拘束の射影で反復のあいだに変わる。乗数の上限へ
//! 換算して持つと、w̃ が小さくなった反復で上限が広がり、細分の累計が上限を超える。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

use blitz_math::{メートル, 逆キログラム};

use super::minimum_thickness::形の最小の厚み;
use crate::xpbd::ラグランジュ乗数;

/// 接触1点が1細分の反復のあいだ持ち越す非貫通の解の状態。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 非貫通の一細分の解の状態 {
    法線のラグランジュ乗数: ラグランジュ乗数,
    詰めた相対補正の長さの累計: メートル, // その細分で実際に適用した法線方向の相対補正の長さの和
}

impl 非貫通の一細分の解の状態 {
    /// 細分の開始の状態。乗数も詰めた長さも零であり、前の細分の値から始める暖機はしない(判断16)。
    pub fn 細分の開始の状態() -> Self {
        Self {
            法線のラグランジュ乗数: ラグランジュ乗数::零(),
            詰めた相対補正の長さの累計: メートル::生成する(0.0),
        }
    }

    /// この細分で累積した法線方向のラグランジュ乗数。摩擦のクーロン円錐と速度段階がこれを読む。
    pub fn 法線のラグランジュ乗数(&self) -> ラグランジュ乗数 {
        self.法線のラグランジュ乗数
    }

    /// この細分でまだ詰めてよい相対補正の長さ。上限に達していれば零である。
    pub(super) fn 残りの補正の長さ(&self, 一細分の補正の長さの上限: 形の最小の厚み) -> メートル {
        let 残り = 一細分の補正の長さの上限.長さ() - self.詰めた相対補正の長さの累計;
        if 残り.値() > 0.0 { 残り } else { メートル::生成する(0.0) }
    }

    /// 乗数の増分を適用した後の状態。詰めた長さへ足すのは、その反復の有効逆質量と増分の積である相対補正の長さである。
    pub(super) fn 増分を適用した状態(&self, 乗数の増分: ラグランジュ乗数, 有効逆質量: 逆キログラム) -> Self {
        Self {
            法線のラグランジュ乗数: self.法線のラグランジュ乗数 + 乗数の増分,
            詰めた相対補正の長さの累計: self.詰めた相対補正の長さの累計 + 乗数の増分 * 有効逆質量,
        }
    }
}
