//! 運動種別の遷移に伴う接触履歴破棄の検査(判断7・判断16)。
//! 遷移した剛体を含む剛体どうし・剛体と静的世界の接触履歴がすべて捨てられることを検証する。

use blitz_math::{ワールド, 変位, 方向};

use super::super::contact_test_fixtures::世界の位置を作る;
use super::super::feature_identity::接触の特徴の識別;
use super::super::non_penetration::fixture::下向きの接触法線;
use super::super::stacked_box_fixture::上下の箱の接触点集合;
use super::super::static_friction::静止摩擦の錨;
use super::super::static_world_partner_id::静的世界の接触相手の識別子;
use super::body_body_key::剛体どうしの接触の鍵;
use super::body_static_key::剛体と静的世界の接触の鍵;
use super::continuation_record::接触の継続の記録;
use super::kinds::{
    剛体と静的世界の接触の履歴, 剛体と静的世界の接触の履歴の項目, 剛体どうしの接触の履歴, 剛体どうしの接触の履歴の項目
};
use crate::rigid_body::{剛体の識別子, 姿勢};

fn 昇順の特徴の識別四つ() -> Vec<接触の特徴の識別> {
    let 接触点集合 = 上下の箱の接触点集合(姿勢::恒等());
    let mut 一覧: Vec<接触の特徴の識別> = 接触点集合.接触点を順に並べる().map(|点| (*点.特徴の識別()).into()).collect();
    一覧.sort_unstable();
    一覧
}

fn テスト用の剛体どうしの項目(
    a: 剛体の識別子, b: 剛体の識別子, 特徴: 接触の特徴の識別
) -> 剛体どうしの接触の履歴の項目 {
    let 鍵 = 剛体どうしの接触の鍵::生成する(a, b, 特徴);
    let 錨 = 静止摩擦の錨::生成する(変位::零(), 変位::零());
    let Ok(法線) = 方向::<ワールド>::生成する(0.0, 1.0, 0.0) else {
        panic!("方向の生成に失敗した");
    };
    let 記録 = 接触の継続の記録::生成する(錨, 法線);
    剛体どうしの接触の履歴の項目::生成する(鍵, 記録)
}

fn テスト用の剛体と静的世界の項目(
    剛体: 剛体の識別子,
    相手: 静的世界の接触相手の識別子,
    特徴: 接触の特徴の識別,
) -> 剛体と静的世界の接触の履歴の項目 {
    let 鍵 = 剛体と静的世界の接触の鍵::生成する(剛体, 相手, 特徴);
    let 錨 = 静止摩擦の錨::生成する(変位::零(), 世界の位置を作る(0.0, 0.0, 0.0));
    let 記録 = 接触の継続の記録::生成する(錨, 下向きの接触法線());
    剛体と静的世界の接触の履歴の項目::生成する(鍵, 記録)
}

#[test]
fn 遷移した剛体を含む接触履歴がすべて捨てられる() {
    let 特徴一覧 = 昇順の特徴の識別四つ();
    let mut 台帳 = crate::rigid_body::剛体の台帳::空();
    let 剛体0 = super::super::contact_test_fixtures::台帳へ登録する(
        &mut 台帳,
        crate::rigid_body::配置::生成する(世界の位置を作る(0.0, 0.0, 0.0), 姿勢::恒等()),
    );
    let 剛体1 = super::super::contact_test_fixtures::台帳へ登録する(
        &mut 台帳,
        crate::rigid_body::配置::生成する(世界の位置を作る(1.0, 0.0, 0.0), 姿勢::恒等()),
    );
    let 剛体2 = super::super::contact_test_fixtures::台帳へ登録する(
        &mut 台帳,
        crate::rigid_body::配置::生成する(世界の位置を作る(2.0, 0.0, 0.0), 姿勢::恒等()),
    );
    let 相手 = 静的世界の接触相手の識別子::生成する(0);

    let mut 剛体間履歴 = 剛体どうしの接触の履歴::見込みの接触点の数で生成する(4);
    let 項目01 = テスト用の剛体どうしの項目(剛体0, 剛体1, 特徴一覧[0]);
    let 項目12 = テスト用の剛体どうしの項目(剛体1, 剛体2, 特徴一覧[1]);
    let 項目02 = テスト用の剛体どうしの項目(剛体0, 剛体2, 特徴一覧[2]);
    let mut 項目一覧 = vec![項目01, 項目02, 項目12];
    項目一覧.sort_unstable_by_key(|項目| 項目.鍵());
    let Ok(()) = 剛体間履歴.細分の終わりの記録で置き換える(&項目一覧) else {
        panic!("履歴の置き換えに失敗した");
    };
    assert_eq!(剛体間履歴.項目一覧().len(), 3);

    let mut 静的履歴 = 剛体と静的世界の接触の履歴::見込みの接触点の数で生成する(4);
    let 静的項目0 = テスト用の剛体と静的世界の項目(剛体0, 相手, 特徴一覧[0]);
    let 静的項目1 = テスト用の剛体と静的世界の項目(剛体1, 相手, 特徴一覧[1]);
    let mut 静的一覧 = vec![静的項目0, 静的項目1];
    静的一覧.sort_unstable_by_key(|項目| 項目.鍵());
    let Ok(()) = 静的履歴.細分の終わりの記録で置き換える(&静的一覧) else {
        panic!("履歴の置き換えに失敗した");
    };
    assert_eq!(静的履歴.項目一覧().len(), 2);

    let 遷移剛体 = 剛体1;
    剛体間履歴.項目を絞り込む(|鍵| !鍵.剛体を含むか(遷移剛体));
    静的履歴.項目を絞り込む(|鍵| !鍵.剛体を含むか(遷移剛体));

    assert_eq!(剛体間履歴.項目一覧().len(), 1);
    assert_eq!(剛体間履歴.項目一覧()[0].鍵().小さい方の剛体(), 剛体0);
    assert_eq!(剛体間履歴.項目一覧()[0].鍵().大きい方の剛体(), 剛体2);

    assert_eq!(静的履歴.項目一覧().len(), 1);
    assert_eq!(静的履歴.項目一覧()[0].鍵().剛体(), 剛体0);
}
