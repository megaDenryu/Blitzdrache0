//! 終了した接触の持ち越す接線の残差が履歴に残らないことの試験(判断24の破棄条件1)。
//! 併走の試験(`correspondence_tests`)から分けているのは、あちらが継続と終了と開始の分かれ方そのものを固定する
//! のに対し、こちらが「終了した接触が持っていた残差が次の細分へ渡らない」ことだけを見るからである。
//! 鍵と項目の材料はあちらが持ち、この試験はそれを借りる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 変位, 方向};

use super::super::contact_test_fixtures::世界の位置を作る;
use super::super::feature_identity::接触の特徴の識別;
use super::super::non_penetration::fixture::下向きの接触法線;
use super::super::static_friction::{持ち越す接線の残差, 静止摩擦の錨};
use super::continuation_record::接触の継続の記録;
use super::correspondence_tests::{昇順の特徴の識別四つ, 鍵を作る, 項目を作る};
use super::kinds::{剛体と静的世界の接触の履歴, 剛体と静的世界の接触の履歴の項目};

const 見込みの接触点の数: usize = 8;

// 残差を持つ1件。終了したときにこの値が次の細分へ渡らないことを見る。
fn 残差を持つ項目(特徴の識別: 接触の特徴の識別) -> 剛体と静的世界の接触の履歴の項目 {
    let 錨 = 静止摩擦の錨::生成する(変位::零(), 世界の位置を作る(0.0, 1.0, 0.0));
    let 残差 = 持ち越す接線の残差::測った変位から生成する(変位::方向へ進む(
        方向::生成する(1.0, 0.0, 0.0).unwrap(),
        メートル::生成する(1.0e-6),
    ));
    剛体と静的世界の接触の履歴の項目::生成する(鍵を作る(特徴の識別), 接触の継続の記録::生成する(錨, 下向きの接触法線(), 残差))
}

#[test]
fn 終了した接触の持ち越す接線の残差は履歴に残らない() {
    let 特徴 = 昇順の特徴の識別四つ();
    let mut 履歴 = 剛体と静的世界の接触の履歴::見込みの接触点の数で生成する(見込みの接触点の数);
    履歴.細分の終わりの記録で置き換える(&[残差を持つ項目(特徴[0])]).unwrap();
    let 新しい細分の接触 = [項目を作る(特徴[1], 5.0)];
    let 結果 = 履歴.新しい細分の接触と併走する(&新しい細分の接触).unwrap();
    assert!(!結果.対応付け一覧()[0].継続か());
    assert_eq!(結果.対応付け一覧()[0].この細分で使う記録().持ち越す接線の残差(), 持ち越す接線の残差::無し);
    履歴.細分の終わりの記録で置き換える(&新しい細分の接触).unwrap();
    assert!(
        履歴
            .項目一覧()
            .iter()
            .all(|項目| 項目.記録().持ち越す接線の残差() == 持ち越す接線の残差::無し)
    );
}
