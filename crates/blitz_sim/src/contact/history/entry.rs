//! 接触の履歴の項目: 鍵と継続の記録の組(判断16)。履歴が鍵の昇順で保つ1件であり、新しい細分の側が併走へ持ち込む1件でもある。
//! 同じ型を両側で使うのは、併走が2つの昇順の一覧を突き合わせる操作であり、片方だけが別の綴りを持つ理由が無いためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断16: 接触の履歴は参加者の組ごとに特徴の識別を鍵に全順序の併走で対応付け、暖機はしない」

/// 接触1点の鍵と、その接触が保つ記録の組。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触の履歴の項目<鍵, 記録> {
    鍵: 鍵,
    記録: 記録,
}

impl<鍵: Ord + Copy, 記録: Copy> 接触の履歴の項目<鍵, 記録> {
    /// 鍵と記録から作る。並びの昇順は履歴の側が検査するため、この生成は検査を持たない。
    pub fn 生成する(鍵: 鍵, 記録: 記録) -> Self {
        Self { 鍵, 記録 }
    }

    /// 併走が突き合わせる鍵。
    pub fn 鍵(&self) -> 鍵 {
        self.鍵
    }

    /// 継続なら引き継ぐ値、開始なら新しく置く値。
    pub fn 記録(&self) -> 記録 {
        self.記録
    }
}
