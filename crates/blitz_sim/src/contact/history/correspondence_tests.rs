// 面と面の接触が返す4つの接触点の特徴の識別を、昇順に並べて取り出す。
fn 昇順の特徴の識別四つ() -> Vec<接触の特徴の識別> {
    let 接触点集合 = 上下の箱の接触点集合(姿勢::恒等());
    let mut 一覧: Vec<接触の特徴の識別> = 接触点集合.接触解法の候補点を順に並べる().map(|点| (*点.特徴の識別()).into()).collect();
    一覧.sort_unstable();
    一覧
}

fn 鍵を作る(特徴の識別: 接触の特徴の識別) -> 剛体と静的世界の接触の鍵 {
    let mut 台帳 = 剛体の台帳::空();
    let 剛体 = 台帳へ登録する(&mut 台帳, 上の箱の配置(姿勢::恒等()));
    剛体と静的世界の接触の鍵::生成する(剛体, 静的世界の接触相手の識別子::生成する(静的世界の番号), 特徴の識別)
}

fn 高さの錨の記録(高さ: f32) -> 剛体と静的世界の接触の継続の記録 {
    接触の継続の記録::生成する(
        静止摩擦の錨::生成する(変位::零(), 世界の位置を作る(0.0, 高さ, 0.0)),
        下向きの接触法線(),
        持ち越す接線の残差::無し,
    )
}

fn 項目を作る(特徴の識別: 接触の特徴の識別, 高さ: f32) -> 剛体と静的世界の接触の履歴の項目 {
    剛体と静的世界の接触の履歴の項目::生成する(鍵を作る(特徴の識別), 高さの錨の記録(高さ))
}

#[test]
fn 継続と終了と開始が鍵の併走で分かれる() {
    let 特徴 = 昇順の特徴の識別四つ();
    let mut 履歴 = 剛体と静的世界の接触の履歴::見込みの接触点の数で生成する(見込みの接触点の数);
    履歴
        .細分の終わりの記録で置き換える(&[項目を作る(特徴[0], 1.0), 項目を作る(特徴[1], 2.0)])
        .unwrap();
    let 新しい細分の接触 = [項目を作る(特徴[1], 9.0), 項目を作る(特徴[2], 9.0)];
    let 結果 = 履歴.新しい細分の接触と併走する(&新しい細分の接触).unwrap();
    assert_eq!(結果.終了した接触の数(), 1);
    assert!(結果.対応付け一覧()[0].継続か());
    assert!(!結果.対応付け一覧()[1].継続か());
    assert_eq!(結果.対応付け一覧()[0].この細分で使う記録(), 高さの錨の記録(2.0));
    assert_eq!(結果.対応付け一覧()[1].この細分で使う記録(), 高さの錨の記録(9.0));
    履歴.細分の終わりの記録で置き換える(&新しい細分の接触).unwrap();
    let 置き換えた後の鍵一覧: Vec<剛体と静的世界の接触の鍵> = 履歴.項目一覧().iter().map(剛体と静的世界の接触の履歴の項目::鍵).collect();
    assert_eq!(置き換えた後の鍵一覧, vec![鍵を作る(特徴[1]), 鍵を作る(特徴[2])]);
}

#[test]
fn 特徴の識別が変わった接触は古い錨を引き継がず新規になる() {
    let 特徴 = 昇順の特徴の識別四つ();
    let mut 履歴 = 剛体と静的世界の接触の履歴::見込みの接触点の数で生成する(見込みの接触点の数);
    履歴.細分の終わりの記録で置き換える(&[項目を作る(特徴[0], 1.0)]).unwrap();
    let 新しい細分の接触 = [項目を作る(特徴[1], 5.0)];
    let 結果 = 履歴.新しい細分の接触と併走する(&新しい細分の接触).unwrap();
    assert_eq!(結果.終了した接触の数(), 1);
    assert!(!結果.対応付け一覧()[0].継続か());
    assert_eq!(結果.対応付け一覧()[0].この細分で使う記録(), 高さの錨の記録(5.0));
}

#[test]
fn 昇順でない一覧は併走も置き換えも型付きエラーで拒む() {
    let 特徴 = 昇順の特徴の識別四つ();
    let 降順 = [項目を作る(特徴[1], 1.0), 項目を作る(特徴[0], 1.0)];
    let 同じ鍵が二つ = [項目を作る(特徴[0], 1.0), 項目を作る(特徴[0], 2.0)];
    let mut 履歴 = 剛体と静的世界の接触の履歴::見込みの接触点の数で生成する(見込みの接触点の数);
    assert!(履歴.新しい細分の接触と併走する(&降順).is_err());
    assert!(履歴.新しい細分の接触と併走する(&同じ鍵が二つ).is_err());
    assert!(履歴.細分の終わりの記録で置き換える(&降順).is_err());
}

#[test]
fn 生成した接触拘束は並べ替えの後に昇順の鍵で併走へ渡せる() {
    let 接触点集合 = 上下の箱の接触点集合(姿勢::恒等());
    let 上の配置 = 上の箱の配置(姿勢::恒等());
    let mut 台帳 = 剛体の台帳::空();
    let 剛体 = 接触に参加する剛体を作る(台帳へ登録する(&mut 台帳, 上の配置), 上の配置);
    let 混合則 = 単一の材質の混合則();
    let mut 組み立て = 接触拘束のバッチの組み立て::生成する(&混合則, コンプライアンス::硬い(), 試験の刻み幅(), 1);
    組み立て
        .剛体と静的世界の接触点集合を積む(&剛体, &静的世界の接触相手を作る(静的世界の番号), &接触点集合)
        .unwrap();
    let mut バッチ = 組み立て.二つのバッチを組み立てる();
    バッチ.鍵の昇順へ並べ替える();
    let 新しい細分の接触: Vec<剛体と静的世界の接触の履歴の項目> = バッチ
        .剛体と静的世界の接触拘束()
        .iter()
        .map(super::super::body_static_contact::剛体と静的世界の接触拘束::併走へ持ち込む履歴の項目)
        .collect();
    let mut 履歴 = 剛体と静的世界の接触の履歴::見込みの接触点の数で生成する(見込みの接触点の数);
    let 結果 = 履歴.新しい細分の接触と併走する(&新しい細分の接触).unwrap();
    assert_eq!(結果.対応付け一覧().len(), 接触点集合.件数());
    assert!(結果.対応付け一覧().iter().all(|対応| !対応.継続か()));
}
