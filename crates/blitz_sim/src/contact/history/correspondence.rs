//! 併走が新しい細分の接触1点へ返す対応付けと、併走1回ぶんの結果(判断16)。
//! 対応付けは継続と開始の2枝である。終了は新しい側に相手が居ない場合であり、返る一覧に現れないため枝を持たず、
//! 件数だけを結果が持つ(呼び出し側が「前の細分に在った接触がいくつ消えたか」を見られるようにするため)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断16: 接触の履歴は参加者の組ごとに特徴の識別を鍵に全順序の併走で対応付け、暖機はしない」

/// 新しい細分の接触1点が、前の細分の履歴とどう対応したか。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 接触の対応付け<記録> {
    /// 同じ鍵が履歴にあった。錨と前の細分の接触法線を履歴から引き継ぐ。
    継続 { 引き継いだ記録: 記録 },
    /// 同じ鍵が履歴に無かった。錨をこの細分の接触点に置いて始める。
    開始 { 始めの記録: 記録 },
}

impl<記録: Copy> 接触の対応付け<記録> {
    /// この細分でこの接触点が使う記録。継続なら引き継いだ値、開始ならこの細分で置いた値である。
    pub fn この細分で使う記録(&self) -> 記録 {
        match self {
            Self::継続 { 引き継いだ記録 } => *引き継いだ記録,
            Self::開始 { 始めの記録 } => *始めの記録,
        }
    }

    /// 前の細分から続いている接触か。
    pub fn 継続か(&self) -> bool {
        matches!(self, Self::継続 { .. })
    }
}

/// 併走1回の結果。新しい側と同じ並びの対応付けと、前の細分にだけ在って消えた接触の件数を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触の併走の結果<'併走の寿命, 記録> {
    対応付け一覧: &'併走の寿命 [接触の対応付け<記録>],
    終了した接触の数: usize,
}

impl<'併走の寿命, 記録: Copy> 接触の併走の結果<'併走の寿命, 記録> {
    // 併走の工程だけが組む。並びと件数の対応は工程が保つ。
    pub(super) fn 併走が組む(対応付け一覧: &'併走の寿命 [接触の対応付け<記録>], 終了した接触の数: usize) -> Self {
        Self {
            対応付け一覧,
            終了した接触の数,
        }
    }

    /// 新しい細分の接触と同じ並びの対応付け。呼び出し側は接触拘束の一覧と添字で対応させる。
    pub fn 対応付け一覧(&self) -> &'併走の寿命 [接触の対応付け<記録>] {
        self.対応付け一覧
    }

    /// 前の細分の履歴にだけ在って、この細分の接触に相手が居なかった件数。
    pub fn 終了した接触の数(&self) -> usize {
        self.終了した接触の数
    }
}
