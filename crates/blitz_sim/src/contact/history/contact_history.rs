//! 接触の履歴: 参加者の組ごとに、接触1点の錨と前の細分の接触法線を鍵の昇順の一覧で保つ型(判断16)。
//! 鍵と記録を型引数にしているのは、剛体どうしと剛体と静的世界で鍵の綴りも錨の形も違う一方、
//! 「昇順の一覧を併走させて継続と終了と開始へ分ける」という振る舞いが同じだからである。参加者の組ごとに別の値を持つ
//! という判断16の要求は、2つの型引数の組で別々の値を作ることで満たす。
//! ハッシュ表を使わないのは、確保を起こし走査の順が実装の詳細に依るためである。併走は確保を起こさず、
//! 順序が入力だけで決まるため決定的である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断16: 接触の履歴は参加者の組ごとに特徴の識別を鍵に全順序の併走で対応付け、暖機はしない」

use super::correspondence::{接触の併走の結果, 接触の対応付け};
use super::entry::接触の履歴の項目;
use super::error::接触の履歴エラー;

/// 1つの参加者の組の接触の履歴。刻みを跨いで剛体の台帳が保持する。
#[derive(Debug, Clone, PartialEq)]
pub struct 接触の履歴<鍵, 記録> {
    項目: Vec<接触の履歴の項目<鍵, 記録>>,
    対応付けの受け皿: Vec<接触の対応付け<記録>>,
}

impl<鍵: Ord + Copy, 記録: Copy> 接触の履歴<鍵, 記録> {
    /// 接触を1つも持たない履歴。見込みの接触点の数ぶんの受け皿を先に確保し、細分ごとの併走で確保を起こさない。
    pub fn 見込みの接触点の数で生成する(見込みの接触点の数: usize) -> Self {
        Self {
            項目: Vec::with_capacity(見込みの接触点の数),
            対応付けの受け皿: Vec::with_capacity(見込みの接触点の数),
        }
    }

    /// 保っている接触の項目。鍵の昇順である。
    pub fn 項目一覧(&self) -> &[接触の履歴の項目<鍵, 記録>] {
        &self.項目
    }

    /// 昇順に並んだ新しい細分の接触と併走して対応付ける。鍵が一致すれば継続、新しい側にだけあれば開始であり、
    /// 履歴にだけあった接触は終了として件数に数える。履歴そのものはここでは書き換えず、細分の終わりに置き換える。
    pub fn 新しい細分の接触と併走する(
        &mut self,
        新しい細分の接触: &[接触の履歴の項目<鍵, 記録>],
    ) -> Result<接触の併走の結果<'_, 記録>, 接触の履歴エラー> {
        鍵の昇順を確かめる(新しい細分の接触)?;
        self.対応付けの受け皿.clear();
        let mut 履歴の添字 = 0;
        let mut 終了した接触の数 = 0;
        for 新しい項目 in 新しい細分の接触 {
            while self.項目.get(履歴の添字).is_some_and(|項目| 項目.鍵() < 新しい項目.鍵()) {
                終了した接触の数 += 1;
                履歴の添字 += 1;
            }
            let 一致した記録 = self
                .項目
                .get(履歴の添字)
                .filter(|項目| 項目.鍵() == 新しい項目.鍵())
                .map(接触の履歴の項目::記録);
            self.対応付けの受け皿.push(match 一致した記録 {
                Some(引き継いだ記録) => {
                    履歴の添字 += 1;
                    接触の対応付け::継続 { 引き継いだ記録 }
                }
                None => 接触の対応付け::開始 {
                    始めの記録: 新しい項目.記録(),
                },
            });
        }
        終了した接触の数 += self.項目.len() - 履歴の添字;
        Ok(接触の併走の結果::併走が組む(&self.対応付けの受け皿, 終了した接触の数))
    }

    /// 細分の終わりの錨とその細分の接触法線で履歴を置き換える。次の細分の併走はこの一覧と突き合わせる。
    pub fn 細分の終わりの記録で置き換える(
        &mut self,
        細分の終わりの接触: &[接触の履歴の項目<鍵, 記録>],
    ) -> Result<(), 接触の履歴エラー> {
        鍵の昇順を確かめる(細分の終わりの接触)?;
        self.項目.clear();
        self.項目.extend_from_slice(細分の終わりの接触);
        Ok(())
    }

    /// 条件を満たす項目だけを残す。運動種別の遷移や剛体の破棄で、特定の剛体を含む履歴を捨てるために使う(判断7・判断16)。
    pub fn 項目を絞り込む<F: Fn(&鍵) -> bool>(&mut self, 条件: F) {
        self.項目.retain(|項目| 条件(&項目.鍵()));
    }
}

// 隣り合う2件の鍵を順に比べるだけの純粋な検査であり、履歴の状態を読まない。
fn 鍵の昇順を確かめる<鍵: Ord + Copy, 記録: Copy>(
    一覧: &[接触の履歴の項目<鍵, 記録>]
) -> Result<(), 接触の履歴エラー> {
    for 添字 in 1..一覧.len() {
        if 一覧[添字 - 1].鍵() >= 一覧[添字].鍵() {
            return Err(接触の履歴エラー::鍵の一覧が昇順でない {
                前の添字: 添字 - 1, 添字
            });
        }
    }
    Ok(())
}
