//! 接触の継続の記録: 継続する接触が前の細分から引き継ぐ3つ(判断16)。静止摩擦の錨と、前の細分の接触法線と、
//! 持ち越す接線の残差(判断24)である。
//! 法線のラグランジュ乗数は引き継がない。細分が収束を担うため乗数の持ち越しが要らず、暖機は反証の独立性を下げるためである。
//! 前の細分の接触法線を持つのは、同じ特徴で対応付いた接触でも法線が急に向きを変えたときに、錨の引き継ぎが意味を失うことを
//! 検出できるようにするためである(何度で急変とみなすかは正本が定めておらず、この作業は値を運ぶところまでを持つ)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断16: 接触の履歴は参加者の組ごとに特徴の識別を鍵に全順序の併走で対応付け、暖機はしない」

use blitz_math::{ワールド, 方向};

use super::super::static_friction::持ち越す接線の残差;

/// 接触1点が刻みを跨いで保つ値。錨の型は参加者の組ごとに違う。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触の継続の記録<錨> {
    錨: 錨,
    前の細分の接触法線: 方向<ワールド>,
    持ち越す接線の残差: 持ち越す接線の残差,
}

impl<錨: Copy> 接触の継続の記録<錨> {
    /// 細分の終わりの錨とその細分の接触法線と、その細分で閉じずに残った接線の残差から作る。
    pub fn 生成する(
        錨: 錨, 前の細分の接触法線: 方向<ワールド>, 持ち越す接線の残差: 持ち越す接線の残差
    ) -> Self {
        Self {
            錨,
            前の細分の接触法線,
            持ち越す接線の残差,
        }
    }

    /// 静止摩擦が接線変位を測る起点。
    pub fn 錨(&self) -> 錨 {
        self.錨
    }

    /// 1つ前の細分でこの接触が持っていた接触法線。
    pub fn 前の細分の接触法線(&self) -> 方向<ワールド> {
        self.前の細分の接触法線
    }

    /// 1つ前の細分でこの接触が閉じずに残した接線の残差(判断24)。次の細分の速度の再構成が1回だけ読む。
    pub fn 持ち越す接線の残差(&self) -> 持ち越す接線の残差 {
        self.持ち越す接線の残差
    }
}
