//! 剛体と剛体の接触の履歴の鍵(判断16)。2つの剛体の識別子を昇順へ正規化した組と、接触の特徴の識別の3つ組である。
//! 正規化が入れ替えるのは識別子だけであり、特徴の識別は入れ替えない(第1の形と第2の形の綴りを交換する口を衝突数学層が
//! 持たないためである)。したがって、逆順で作った鍵は同じ鍵になりながら、向きの違う特徴と錨と法線を指す。
//! これを避けるため、接触点集合を積む工程が剛体aの識別子を剛体bの識別子より小さいことに強制する(`batch_builder_push`)。
//! 正規化をここに残すのは、強制が破れたときに鍵の一致で気づけるようにするためである。
//! 全順序を持つのは、履歴を鍵の昇順の一覧で保ち、新しい細分の接触と併走して対応付けるためである(判断17の反復の順序も同じ昇順を読む)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断16: 接触の履歴は参加者の組ごとに特徴の識別を鍵に全順序の併走で対応付け、暖機はしない」

use super::super::feature_identity::接触の特徴の識別;
use crate::rigid_body::剛体の識別子;

/// 剛体と剛体の接触点1つを刻みを跨いで指す鍵。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 剛体どうしの接触の鍵 {
    小さい方の剛体: 剛体の識別子,
    大きい方の剛体: 剛体の識別子,
    特徴の識別: 接触の特徴の識別,
}

impl 剛体どうしの接触の鍵 {
    /// 2つの剛体の識別子を昇順へ並べ替えて作る。同じ識別子どうしの接触と昇順でない接触は、どちらも接触点集合を積む
    /// 工程が先に拒むため、ここに検査は無い。
    pub fn 生成する(第1の剛体: 剛体の識別子, 第2の剛体: 剛体の識別子, 特徴の識別: 接触の特徴の識別) -> Self {
        let (小さい方の剛体, 大きい方の剛体) = if 第1の剛体 <= 第2の剛体 {
            (第1の剛体, 第2の剛体)
        } else {
            (第2の剛体, 第1の剛体)
        };
        Self {
            小さい方の剛体,
            大きい方の剛体,
            特徴の識別,
        }
    }

    /// 昇順に並べたときに先に来る剛体の識別子。
    pub fn 小さい方の剛体(&self) -> 剛体の識別子 {
        self.小さい方の剛体
    }

    /// 昇順に並べたときに後に来る剛体の識別子。
    pub fn 大きい方の剛体(&self) -> 剛体の識別子 {
        self.大きい方の剛体
    }

    /// この接触点がどの特徴どうしで生まれたかの綴り。
    pub fn 特徴の識別(&self) -> 接触の特徴の識別 {
        self.特徴の識別
    }

    /// 指定した剛体がこの接触拘束に参加しているか。
    pub fn 剛体を含むか(&self, 剛体: 剛体の識別子) -> bool {
        self.小さい方の剛体 == 剛体 || self.大きい方の剛体 == 剛体
    }
}
