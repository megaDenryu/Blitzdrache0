//! 剛体と静的世界の接触の履歴の鍵(判断16)。剛体の識別子・静的世界の接触相手の識別子・接触の特徴の識別の3つ組である。
//! 剛体どうしの鍵と違って昇順の正規化を持たないのは、2つの識別子が別の型であり、どちらが第1の参加者かが型で決まっているためである。
//! 全順序を持つのは、履歴を鍵の昇順の一覧で保ち、新しい細分の接触と併走して対応付けるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断16: 接触の履歴は参加者の組ごとに特徴の識別を鍵に全順序の併走で対応付け、暖機はしない」

use super::super::feature_identity::接触の特徴の識別;
use super::super::static_world_partner_id::静的世界の接触相手の識別子;
use crate::rigid_body::剛体の識別子;

/// 剛体と静的世界の接触点1つを刻みを跨いで指す鍵。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 剛体と静的世界の接触の鍵 {
    剛体: 剛体の識別子,
    静的世界の接触相手: 静的世界の接触相手の識別子,
    特徴の識別: 接触の特徴の識別,
}

impl 剛体と静的世界の接触の鍵 {
    /// 3つの綴りから作る。どの組み合わせも正当な鍵であるため検査は無い。
    pub fn 生成する(
        剛体: 剛体の識別子, 静的世界の接触相手: 静的世界の接触相手の識別子, 特徴の識別: 接触の特徴の識別
    ) -> Self {
        Self {
            剛体,
            静的世界の接触相手,
            特徴の識別,
        }
    }

    /// 接触の第1の参加者である剛体の識別子。
    pub fn 剛体(&self) -> 剛体の識別子 {
        self.剛体
    }

    /// 接触の第2の参加者である静的世界の接触相手の識別子。
    pub fn 静的世界の接触相手(&self) -> 静的世界の接触相手の識別子 {
        self.静的世界の接触相手
    }

    /// この接触点がどの特徴どうしで生まれたかの綴り。
    pub fn 特徴の識別(&self) -> 接触の特徴の識別 {
        self.特徴の識別
    }
}
