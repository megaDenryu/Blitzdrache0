//! 上下に積んだ2つの箱の材料。半分の長さ0.5メートルの立方体を2つ、y方向に0.05メートル食い込ませて並べる。
//! 上の箱の姿勢を差し替えられるようにしているのは、局所点への写しが姿勢を通ることを、恒等でない姿勢でも確かめるためである。
//! 接触点集合は面どうしの接触になり、切り抜きが上の箱の底面の4つの角を返す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_collision::contact_set::{接触点集合, 直方体どうしの接触の特徴の対};

use super::contact_manifold_fixture::{二つの形の運動から接触生成の余白を導く, 直方体どうしの接触点集合を求める};
use super::contact_test_fixtures::{世界の位置を作る, 形の位置を作る, 直方体を作る};
use crate::rigid_body::{姿勢, 運動状態, 配置};

pub(super) const 半分の長さ: f32 = 0.5;
pub(super) const 食い込み: f32 = 0.05;

// 下の箱の上面がy=0に来るように置き、上の箱をそこから食い込みのぶんだけ沈める。
pub(super) fn 上の箱の重心の高さ() -> f32 {
    半分の長さ - 食い込み
}

pub(super) fn 上の箱の配置(姿勢: 姿勢) -> 配置 {
    配置::生成する(世界の位置を作る(0.0, 上の箱の重心の高さ(), 0.0), 姿勢)
}

pub(super) fn 下の箱の配置() -> 配置 {
    配置::生成する(世界の位置を作る(0.0, -半分の長さ, 0.0), 姿勢::恒等())
}

pub(super) fn 上下の箱の接触点集合(上の姿勢: 姿勢) -> 接触点集合<直方体どうしの接触の特徴の対> {
    let 上の箱 = 直方体を作る(形の位置を作る(0.0, 上の箱の重心の高さ(), 0.0), 上の姿勢, 半分の長さ);
    let 下の箱 = 直方体を作る(形の位置を作る(0.0, -半分の長さ, 0.0), 姿勢::恒等(), 半分の長さ);
    let 余白 = 二つの形の運動から接触生成の余白を導く(&上の箱, 運動状態::静止(), &下の箱, 運動状態::静止());
    直方体どうしの接触点集合を求める(&上の箱, &下の箱, 余白)
}

// 鉛直軸のまわりに90度回した姿勢。立方体であるため接触の形は変わらず、局所点への写しだけが姿勢を通る。
pub(super) fn 鉛直軸まわりに四分の一回した姿勢() -> 姿勢 {
    let 半角の正弦 = std::f32::consts::FRAC_1_SQRT_2;
    姿勢::生成する(0.0, 半角の正弦, 0.0, 半角の正弦).unwrap()
}
