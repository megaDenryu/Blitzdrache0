//! 接触生成の余白を導く形の運動: 接触点集合を作る2つの形のうち片方について、その細分のあいだに形の角が
//! どれだけ動きうるかを決める量の組である(判断11)。並進速度・角速度・外接半径・原点から離れうる長さの4つを
//! 1つの値で持つ。
//! 4つを1つにするのは、余白の導出がこの4つを常に揃って読み、揃っていない組み合わせが導出にとって意味を
//! 持たないためである。形そのものを保たないのは、導出が形の向きを読まないためである。参照面は接触点集合を
//! 組んだ後に決まるため、導出の時点では射影する向きが無い。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use blitz_collision::shape::任意姿勢の直方体;
use blitz_math::{メートル, メートル毎秒, ローカル, ワールド, 変位, 角速度, 速度};

use crate::rigid_body::運動状態;

/// 接触点集合を作る形1つの、その細分の運動と大きさ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 接触生成の余白を導く形の運動 {
    並進速度: 速度<ワールド>,
    角速度: 角速度<ワールド>,
    外接半径: メートル,
    原点から離れうる長さ: メートル,
}

impl 接触生成の余白を導く形の運動 {
    /// この細分の開始時点の速度を持つ形。予測の配置を作るときに使う速度をそのまま受け取る。
    pub(in crate::contact) fn 動く形から生成する(直方体: &任意姿勢の直方体, 運動状態: 運動状態) -> Self {
        Self {
            並進速度: 運動状態.並進速度(),
            角速度: 運動状態.角速度(),
            外接半径: 外接半径を求める(直方体),
            原点から離れうる長さ: 原点から離れうる長さを求める(直方体),
        }
    }

    /// この細分で動かない形。静的世界の接触相手と静的な剛体がこれである。
    pub(in crate::contact) fn 静止した形から生成する(直方体: &任意姿勢の直方体) -> Self {
        Self::動く形から生成する(直方体, 運動状態::静止())
    }

    /// 回転だけでこの形の角が持ちうる速さの上限 |ω| R。角速度 ω で回る剛体のどの点も、重心から最も遠い頂点までの
    /// 長さ R を腕として、これを超える速さを持たない。
    pub(in crate::contact) fn 角が回転で動きうる速さ(&self) -> メートル毎秒 {
        self.角速度.長さ() * self.外接半径
    }

    /// 中心から最も遠い頂点までの長さ。回転で動く点の速さの腕の上限である。
    pub(in crate::contact) fn 外接半径(&self) -> メートル {
        self.外接半径
    }

    pub(in crate::contact) fn 並進速度(&self) -> 速度<ワールド> {
        self.並進速度
    }

    /// この形の点が座標系の原点から離れうる長さの上限。座標を単精度で表す刻みがこの長さで決まる。
    pub(in crate::contact) fn 原点から離れうる長さ(&self) -> メートル {
        self.原点から離れうる長さ
    }
}

// 中心から最も遠い頂点までの長さ。軸ごとの半分の長さは回転で変わらないため、回転を掛けずに求まる。
// 3つの軸に対して対等な計算であるためレシーバを持たない。
fn 外接半径を求める(直方体: &任意姿勢の直方体) -> メートル {
    let 半分 = 直方体.軸ごとの半分の長さ();
    変位::<ローカル>::成分から生成する(半分.x(), 半分.y(), 半分.z()).長さ()
}

// この形の点が座標系の原点から離れうる長さ。中心までの長さに外接半径を足したものである。
fn 原点から離れうる長さを求める(直方体: &任意姿勢の直方体) -> メートル {
    let 中心 = 直方体.中心();
    let 中心までの長さ = 変位::<ローカル>::成分から生成する(中心.x(), 中心.y(), 中心.z()).長さ();
    中心までの長さ + 外接半径を求める(直方体)
}
