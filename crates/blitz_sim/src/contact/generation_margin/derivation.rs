//! 接触生成の余白の導出(判断11)。剛体の対ごと・細分ごとに、その細分のあいだに2つの形の角が動きうる長さを求め、
//! `blitz_collision` の問い合わせへ渡す接触生成の余白にする。`blitz_collision` は値の意味を知らず、受け取った長さを
//! 使うだけである。
//!
//! 余白 = max(細分中の相対運動から導いた長さ, 静穏とみなす運動から導いた下限, 解法が区別できない長さの下限) である。
//! 相対運動から導いた長さは Δt × (|ω_1| R_1 + |ω_2| R_2 + |v_1 − v_2|) であり、ω と v はその細分の開始時点の
//! 角速度と並進速度である(予測の配置を作るときに使う速度と同じもの)。接触点集合は予測した配置で組むため、
//! 角がその細分に動きうる長さはその速度で上から押さえられる。並進の項は相対の並進速度の大きさを丸ごと入れる。
//! 参照面は接触点集合を組んだ後に決まるため、導出の時点では射影する向きが無い。
//! 下限は2つある。1つ目は、判断18が静穏と判定する速さで動く対の角がその細分に動きうる長さ
//! Δt (ω_休止 R_1 + ω_休止 R_2 + 2 v_休止) である。判断18はこの速さ以下の剛体を動いていないものと見なして
//! 休止させるため、この長さより小さい余白は、剛体の側が止まっていると見なしている対の候補点を細分ごとに
//! 入れ替えることになる。並進の項が 2 v_休止 なのは、判断18が島の各動的剛体へ |v| ≤ v_休止 を課すため、
//! 静穏な2つの剛体の相対の並進速度が三角不等式から |v_1 − v_2| ≤ |v_1| + |v_2| ≤ 2 v_休止 になるためである。
//! 静的世界との対では相手の速度が0であるためこの下限は保守的になるが、`接触生成の余白を導く形の運動` は
//! 静止した形と速度0の動的な形を区別しないため、場合分けを足さない。2つ目は、非貫通の解法が食い込みと
//! 区別できない長さである。それより小さい隔たりで角を落とすと、非貫通が収束して食い込みが零へ近づくほど角が
//! 落ちるというIssue #66の症状が戻る。
//!
//! 幾何に由来する上限をここでは置かない。導出が走るのは参照面が決まる前の段階であり、その段階で使える形の量
//! (最小の厚み等)は接触生成の余白の普遍的な上限ではないためである。厚みの無い三角形が形として存在する以上、
//! 形の厚みを上限にすると余白が0へ潰れ、上の2つの下限を破る。`blitz_collision` は参照面が決まった後の
//! 切り抜きの有限個の角だけを候補にするため、この段階で偽の上限を置かない方を採る。
//! 高速で動く対の候補点が広がりすぎることが実測で問題になったときは、参照面が決まった後に導ける幾何学的な上限を
//! 別途設計する(形の最小の厚みを参照面の未確定な段階へ流用しない)。
//! 2つの形を対等に読む計算であるため、どちらかの形のメソッドにせず自由関数にしている。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use blitz_collision::contact_set::{接触点集合の問い合わせエラー, 接触生成の余白メートル};
use blitz_math::メートル;

use super::motion::接触生成の余白を導く形の運動;
use crate::contact::contact_thresholds::{休止と判定する並進速度の閾値, 休止と判定する角速度の閾値};
use crate::xpbd::刻み幅;

// 単位の向き n は Σ_k n_k² = 1 を満たすため、成分の絶対値の和は √3 を超えない。
const 三つの軸の向きの成分の絶対値の和の上限: f32 = 1.732_050_9;

// 座標を単精度へ収めるときの量子化の幅は、隣の表現できる値との差の半分である。
// 参照: `contact_projection_row/participant.rs` の同じ比。
const 表現の刻みから座標の量子化への比: f32 = 0.5;

// 静穏な2つの剛体の相対の並進速度を v_休止 の何倍で押さえるか。判断18が各動的剛体へ |v| ≤ v_休止 を課すため、
// 三角不等式から |v_1 − v_2| ≤ 2 v_休止 である。
const 静穏な二つの剛体の相対の並進速度が休止の閾値を超えない倍率: f32 = 2.0;

/// この細分のあいだに2つの形の角が動きうる長さを、接触生成の余白として求める。
pub(in crate::contact) fn 細分の運動から接触生成の余白を導く(
    第1: &接触生成の余白を導く形の運動,
    第2: &接触生成の余白を導く形の運動,
    細分の刻み幅: 刻み幅,
) -> Result<接触生成の余白メートル, 接触点集合の問い合わせエラー> {
    let 角が動きうる速さ = 第1.角が回転で動きうる速さ() + 第2.角が回転で動きうる速さ();
    let 相対の並進の速さ = (第1.並進速度() - 第2.並進速度()).長さ();
    let 運動から求めた長さ = (角が動きうる速さ + 相対の並進の速さ) * 細分の刻み幅.秒();
    let 下限 = 長さの大きい方(
        静穏と判定される運動で角が動きうる長さ(第1, 第2, 細分の刻み幅),
        解法が食い込みと区別できない長さ(第1, 第2),
    );
    let 余白 = 長さの大きい方(運動から求めた長さ, 下限);
    println!("接触生成の余白の計器 {:.9}", 余白.値());
    接触生成の余白メートル::生成する(f64::from(余白.値()))
}

// 判断18が静穏と判定する速さで動く2つの形の角が、その細分に動きうる長さ Δt (ω_休止 R_1 + ω_休止 R_2 + 2 v_休止)。
// 実際の速度がこの閾値以下である対では、導いた余白がこの長さで一定になり、細分ごとに候補点を保つ範囲が動かない。
// 並進の項の2倍は、静穏な2つの剛体が互いに逆向きへ v_休止 で動く場合の相対の並進速度を覆うためである。
// 2つの形に対して対等な計算であるためレシーバを持たない。
fn 静穏と判定される運動で角が動きうる長さ(
    第1: &接触生成の余白を導く形の運動,
    第2: &接触生成の余白を導く形の運動,
    細分の刻み幅: 刻み幅,
) -> メートル {
    let 回る速さ = 休止と判定する角速度の閾値();
    let 静穏な相対の並進の速さ = 休止と判定する並進速度の閾値().比で伸ばす(静穏な二つの剛体の相対の並進速度が休止の閾値を超えない倍率);
    let 角の速さ = 回る速さ * 第1.外接半径() + 回る速さ * 第2.外接半径() + 静穏な相対の並進の速さ;
    角の速さ * 細分の刻み幅.秒()
}

// 2つの長さのうち大きい方。余白は3つの長さの最大であり、この工程を2回重ねてその最大を採る。
fn 長さの大きい方(第1の長さ: メートル, 第2の長さ: メートル) -> メートル {
    if 第1の長さ < 第2の長さ { 第2の長さ } else { 第1の長さ }
}

// 非貫通の解法がこの2つの形の接触点で「解けた」と見なす長さの上限。行の許容差は
// Σ_k |n_k| (ulp(p_k) + ulp(q_k)) ÷ 2 であり(`contact_projection_row/row_gradient.rs`)、法線の向きは導出の時点で
// 決まっていないため、成分の絶対値の和の上限 √3 で上から押さえる。座標の刻みは、その形の点が原点から離れうる
// 長さで押さえる(刻みは絶対値について単調である)。
// 2つの形に対して対等な計算であるためレシーバを持たない。
fn 解法が食い込みと区別できない長さ(
    第1: &接触生成の余白を導く形の運動, 第2: &接触生成の余白を導く形の運動
) -> メートル {
    let 二つの座標の刻み = 第1.原点から離れうる長さ().表現の刻み幅() + 第2.原点から離れうる長さ().表現の刻み幅();
    二つの座標の刻み * (表現の刻みから座標の量子化への比 * 三つの軸の向きの成分の絶対値の和の上限)
}
