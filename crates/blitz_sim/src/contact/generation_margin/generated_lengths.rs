//! 接触点集合の生成が読む2つの長さ(判断11)。接触生成の余白と、参照軸の選択で外積の軸へ切り替える優位幅である。
//! 2つを1つの値にするのは、同じ工程が同じ入力から対で導き、同じ問い合わせへ揃って渡されるためである。
//! 呼び出し側に2回導かせると、片方だけを別の刻み幅や別の運動から導く取り違えを型が止められない。
//! **1つの値にしても2つの意味は混ざらない。** 余白は切り抜きが参照面の外の角を候補点として残す範囲であり、
//! 優位幅は参照軸の選択で外積の軸へ切り替えるために要求する優位である。読む口を別々に持つのはそのためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use blitz_collision::contact_set::{外積の軸へ切り替える優位幅メートル, 接触生成の余白メートル};

/// 1つの対の1つの細分について導いた、接触点集合の生成が読む2つの長さ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::contact) struct 接触点集合の生成が読む長さ {
    接触生成の余白: 接触生成の余白メートル,
    外積の軸へ切り替える優位幅: 外積の軸へ切り替える優位幅メートル,
}

impl 接触点集合の生成が読む長さ {
    pub(super) fn 二つの長さから組む(
        接触生成の余白: 接触生成の余白メートル,
        外積の軸へ切り替える優位幅: 外積の軸へ切り替える優位幅メートル,
    ) -> Self {
        Self {
            接触生成の余白,
            外積の軸へ切り替える優位幅,
        }
    }

    /// 切り抜きが参照面の外へ出た角を候補点として残す範囲。
    pub(in crate::contact) fn 接触生成の余白(&self) -> 接触生成の余白メートル {
        self.接触生成の余白
    }

    /// 参照軸の選択で外積の軸へ切り替えるために要求する優位の長さ。
    pub(in crate::contact) fn 外積の軸へ切り替える優位幅(&self) -> 外積の軸へ切り替える優位幅メートル {
        self.外積の軸へ切り替える優位幅
    }
}
