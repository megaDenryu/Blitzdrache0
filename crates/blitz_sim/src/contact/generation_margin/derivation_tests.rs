//! 接触生成の余白の導出の反証(判断11)。静止した対で静穏の閾値から求めた下限が返ること、回る速さに比例して
//! 余白が伸びること、厚みの無い板が相手でも余白が下限を下回らないこと、運動の項が下限を超えるときに幾何の
//! 上限で頭打ちにならないこと、静止した相手が項を足さないことを固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_collision::shape::{任意姿勢の直方体, 直方体の軸ごとの半分の長さ};
use blitz_math::{クォータニオン, メートル, ラジアン毎秒, ローカル, ワールド, 位置, 秒, 角速度, 速度};

use super::derivation::細分の運動から接触生成の余白を導く;
use super::motion::接触生成の余白を導く形の運動;
use crate::rigid_body::運動状態;
use crate::xpbd::刻み幅;

const 半分の長さ: f32 = 0.5;
const 立方体の外接半径: f64 = 0.866_025_4;
const 立方体の厚み: f64 = 1.0;
const 厚みの無い板の外接半径: f64 = std::f64::consts::FRAC_1_SQRT_2;
const 試験の細分の刻み幅の秒: f32 = 1.0 / 480.0;

fn 試験の刻み幅() -> 刻み幅 {
    刻み幅::生成する(秒::生成する(試験の細分の刻み幅の秒)).unwrap()
}

fn 立方体(高さ: f32) -> 任意姿勢の直方体 {
    let 半分 = 直方体の軸ごとの半分の長さ::生成する([メートル::生成する(半分の長さ); 3]).unwrap();
    let 中心 = 位置::<ローカル>::生成する(メートル::生成する(0.0), メートル::生成する(高さ), メートル::生成する(0.0));
    任意姿勢の直方体::生成する(中心, クォータニオン::軸が一致する回転(), 半分).unwrap()
}

fn 厚みの無い板(高さ: f32) -> 任意姿勢の直方体 {
    let 半分 = 直方体の軸ごとの半分の長さ::生成する(
        [メートル::生成する(半分の長さ), メートル::生成する(0.0), メートル::生成する(半分の長さ)],
    )
    .unwrap();
    let 中心 = 位置::<ローカル>::生成する(メートル::生成する(0.0), メートル::生成する(高さ), メートル::生成する(0.0));
    任意姿勢の直方体::生成する(中心, クォータニオン::軸が一致する回転(), 半分).unwrap()
}

fn 回る運動状態(回る速さ: f32) -> 運動状態 {
    let 角速度 = 角速度::<ワールド>::成分から生成する(
        ラジアン毎秒::生成する(0.0),
        ラジアン毎秒::生成する(0.0),
        ラジアン毎秒::生成する(回る速さ),
    );
    運動状態::生成する(速度::零(), 角速度)
}

fn 上下の立方体の余白(上の運動状態: 運動状態, 下の運動状態: 運動状態) -> f64 {
    細分の運動から接触生成の余白を導く(
        &接触生成の余白を導く形の運動::動く形から生成する(&立方体(0.5), 上の運動状態),
        &接触生成の余白を導く形の運動::動く形から生成する(&立方体(-0.5), 下の運動状態),
        試験の刻み幅(),
    )
    .unwrap()
    .値()
}

// 単精度の乗算と加算が積み重なる比較の許容差。長さの桁(1e-3以下)に対して十分に細かい。
const 比較の許容差: f64 = 1.0e-9;

// 長さが1メートルの桁になる場面の相対の許容差。単精度の刻みが上の絶対の許容差を超えるため、そこでは比で見る。
const 単精度の刻みで見る相対の許容差: f64 = 1.0e-6;

// 静穏と判定される運動で2つの立方体の角が1細分に動きうる長さ Δt (ω_休止 (R_1 + R_2) + v_休止)。
// ω_休止 = 0.05ラジアン毎秒、v_休止 = 0.01メートル毎秒である(判断18)。
fn 静穏の閾値から求めた下限() -> f64 {
    (0.05 * 立方体の外接半径 * 2.0 + 0.01) * f64::from(試験の細分の刻み幅の秒)
}

#[test]
fn 静止した二つの剛体では静穏の閾値から求めた下限が返る() {
    let 余白 = 上下の立方体の余白(運動状態::静止(), 運動状態::静止());
    let 期待する下限 = 静穏の閾値から求めた下限();
    assert!(
        (余白 - 期待する下限).abs() < 比較の許容差,
        "静止した対の余白{余白}が静穏の閾値から求めた下限{期待する下限}と違う"
    );
}

#[test]
fn 回る速さを二倍にすると余白の運動の項が二倍になる() {
    let 一倍 = 上下の立方体の余白(回る運動状態(1.0), 運動状態::静止());
    let 二倍 = 上下の立方体の余白(回る運動状態(2.0), 運動状態::静止());
    let 期待する一倍 = 立方体の外接半径 * f64::from(試験の細分の刻み幅の秒);
    assert!(一倍 > 静穏の閾値から求めた下限(), "回る速さ1の余白{一倍}が下限で頭打ちになっている");
    assert!(
        (一倍 - 期待する一倍).abs() < 比較の許容差,
        "回る速さ1の余白が{一倍}で期待値{期待する一倍}と違う"
    );
    assert!(
        (二倍 - 一倍 * 2.0).abs() < 比較の許容差,
        "回る速さを2倍にした余白{二倍}が1倍{一倍}の2倍でない"
    );
}

#[test]
fn 厚みの無い板が相手でも余白は静穏の閾値から求めた下限を下回らない() {
    let 余白 = 細分の運動から接触生成の余白を導く(
        &接触生成の余白を導く形の運動::静止した形から生成する(&立方体(0.5)),
        &接触生成の余白を導く形の運動::静止した形から生成する(&厚みの無い板(0.0)),
        試験の刻み幅(),
    )
    .unwrap()
    .値();
    let 期待する下限 = (0.05 * (立方体の外接半径 + 厚みの無い板の外接半径) + 0.01) * f64::from(試験の細分の刻み幅の秒);
    assert!(
        (余白 - 期待する下限).abs() < 比較の許容差,
        "厚み0の板を相手にした余白{余白}が静穏の閾値から求めた下限{期待する下限}と違う"
    );
}

#[test]
fn 運動の項が下限を超えるときは幾何の上限で頭打ちにならない() {
    let 回る速さ = 1000.0;
    let 余白 = 上下の立方体の余白(回る運動状態(回る速さ), 運動状態::静止());
    let 期待する運動の項 = f64::from(回る速さ) * 立方体の外接半径 * f64::from(試験の細分の刻み幅の秒);
    assert!(
        期待する運動の項 > 立方体の厚み,
        "試験の運動の項{期待する運動の項}が立方体の厚み{立方体の厚み}を超えていないため頭打ちの不在を示せない"
    );
    assert!(
        (余白 - 期待する運動の項).abs() < 期待する運動の項 * 単精度の刻みで見る相対の許容差,
        "余白{余白}が運動の項{期待する運動の項}と違い、幾何の上限で頭打ちになっている"
    );
}

#[test]
fn 静止した形の相手は余白へ項を足さない() {
    let 動く相手 = 上下の立方体の余白(回る運動状態(1.0), 運動状態::静止());
    let 静止した相手 = 細分の運動から接触生成の余白を導く(
        &接触生成の余白を導く形の運動::動く形から生成する(&立方体(0.5), 回る運動状態(1.0)),
        &接触生成の余白を導く形の運動::静止した形から生成する(&立方体(-0.5)),
        試験の刻み幅(),
    )
    .unwrap()
    .値();
    assert!(
        (静止した相手 - 動く相手).abs() < 比較の許容差,
        "静止した形から組んだ相手の余白{静止した相手}が、静止の運動状態を渡した余白{動く相手}と違う"
    );
}
