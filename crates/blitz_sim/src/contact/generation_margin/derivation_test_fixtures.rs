//! 接触生成の余白の導出の反証が共有する材料(判断11)。試験の刻み幅・立方体・厚みの無い板・回る運動状態・
//! 上下に並進する運動状態・上下に重ねた立方体の対の余白・静穏の閾値から求めた下限を持つ。
//! 下限の反証と運動の項の反証はどちらも同じ形を同じ刻み幅で測り、両者が同じ期待値の式を読む。材料をここへ
//! 集めるのは、2つの反証がそれぞれ自前の形と刻み幅を持つと、片方だけを直したときに期待値が静かにずれるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_collision::shape::{任意姿勢の直方体, 直方体の軸ごとの半分の長さ};
use blitz_math::{
    クォータニオン, メートル, メートル毎秒, ラジアン毎秒, ローカル, ワールド, 位置, 秒, 角速度, 速度
};

use super::derivation::細分の運動から接触生成の余白を導く;
use super::motion::接触生成の余白を導く形の運動;
use crate::rigid_body::運動状態;
use crate::xpbd::刻み幅;

const 半分の長さ: f32 = 0.5;
pub(super) const 立方体の外接半径: f64 = 0.866_025_4;
pub(super) const 立方体の厚み: f64 = 1.0;
pub(super) const 厚みの無い板の外接半径: f64 = std::f64::consts::FRAC_1_SQRT_2;
pub(super) const 試験の細分の刻み幅の秒: f32 = 1.0 / 480.0;
pub(super) const 反証が写した休止と判定する角速度の閾値: f32 = 0.05; // ラジアン毎秒。判断18の ω_休止 を反証の側へ手で写した値
pub(super) const 反証が写した休止と判定する並進速度の閾値: f32 = 0.01; // メートル毎秒。判断18の v_休止 を反証の側へ手で写した値

// 単精度の乗算と加算が積み重なる比較の許容差。長さの桁(1e-3以下)に対して十分に細かい。
pub(super) const 比較の許容差: f64 = 1.0e-9;

pub(super) fn 試験の刻み幅() -> 刻み幅 {
    刻み幅::生成する(秒::生成する(試験の細分の刻み幅の秒)).unwrap()
}

pub(super) fn 立方体(高さ: f32) -> 任意姿勢の直方体 {
    let 半分 = 直方体の軸ごとの半分の長さ::生成する([メートル::生成する(半分の長さ); 3]).unwrap();
    任意姿勢の直方体::生成する(その高さの中心(高さ), クォータニオン::軸が一致する回転(), 半分).unwrap()
}

// 天頂の軸の半分の長さが0の直方体。形として在りうる厚みの無い板であり、厚みを余白の上限に使うと余白が0へ潰れる。
pub(super) fn 厚みの無い板(高さ: f32) -> 任意姿勢の直方体 {
    let 半分 = 直方体の軸ごとの半分の長さ::生成する(
        [メートル::生成する(半分の長さ), メートル::生成する(0.0), メートル::生成する(半分の長さ)],
    )
    .unwrap();
    任意姿勢の直方体::生成する(その高さの中心(高さ), クォータニオン::軸が一致する回転(), 半分).unwrap()
}

fn その高さの中心(高さ: f32) -> 位置<ローカル> {
    位置::<ローカル>::生成する(メートル::生成する(0.0), メートル::生成する(高さ), メートル::生成する(0.0))
}

pub(super) fn 回る運動状態(回る速さ: f32) -> 運動状態 {
    let 角速度 = 角速度::<ワールド>::成分から生成する(
        ラジアン毎秒::生成する(0.0),
        ラジアン毎秒::生成する(0.0),
        ラジアン毎秒::生成する(回る速さ),
    );
    運動状態::生成する(速度::零(), 角速度)
}

pub(super) fn 上下に並進する運動状態(上へ向かう速さ: f32) -> 運動状態 {
    let 並進速度 = 速度::<ワールド>::成分から生成する(
        メートル毎秒::生成する(0.0),
        メートル毎秒::生成する(上へ向かう速さ),
        メートル毎秒::生成する(0.0),
    );
    運動状態::生成する(並進速度, 角速度::零())
}

pub(super) fn 上下の立方体の余白(上の運動状態: 運動状態, 下の運動状態: 運動状態) -> f64 {
    細分の運動から接触生成の余白を導く(
        &接触生成の余白を導く形の運動::動く形から生成する(&立方体(0.5), 上の運動状態),
        &接触生成の余白を導く形の運動::動く形から生成する(&立方体(-0.5), 下の運動状態),
        試験の刻み幅(),
    )
    .unwrap()
    .値()
}

// 静穏と判定される運動で2つの立方体の角が1細分に動きうる長さ Δt (ω_休止 (R_1 + R_2) + 2 v_休止)。
pub(super) fn 静穏の閾値から求めた下限() -> f64 {
    二つの外接半径から静穏の下限を求める(立方体の外接半径, 立方体の外接半径)
}

// 判断18の静穏の閾値から下限を組み立てる式。相手の形が変わると外接半径だけが変わるため、2つの半径で受ける。
// 並進の項が 2 v_休止 なのは、判断18が各動的剛体へ |v| ≤ v_休止 を課すため、静穏な2つの剛体の相対の並進速度が
// 三角不等式から 2 v_休止 で押さえられるためである。
pub(super) fn 二つの外接半径から静穏の下限を求める(第1の外接半径: f64, 第2の外接半径: f64) -> f64 {
    let 静穏な相対の並進の速さ = 2.0 * f64::from(反証が写した休止と判定する並進速度の閾値);
    (f64::from(反証が写した休止と判定する角速度の閾値) * (第1の外接半径 + 第2の外接半径) + 静穏な相対の並進の速さ) * f64::from(試験の細分の刻み幅の秒)
}
