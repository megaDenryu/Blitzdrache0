//! 接触生成の余白の導出の下限の反証(判断11)。余白が下回ってはならない長さを固定する。
//! 固定するのは3つである。静止した対では静穏の閾値から求めた下限がそのまま返ること、相手が厚みの無い板でも
//! 余白がその下限を下回らないこと、および2つの動的剛体が互いに逆向きへ v_休止 で動く対でも余白がその下限の
//! ままであることである。2つ目は、形の最小の厚みを余白の上限に使う設計を撤回した根拠をそのまま反証にした
//! ものであり、上限を使う実装ではこの場面の上限が0になって下限を破る。3つ目は、下限の並進の項が 2 v_休止 で
//! あることを固定するものであり、1物体分の v_休止 しか足さない実装ではこの場面の期待値と余白が食い違う。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use super::derivation::細分の運動から接触生成の余白を導く;
use super::derivation_test_fixtures::{
    上下に並進する運動状態, 上下の立方体の余白, 二つの外接半径から静穏の下限を求める, 厚みの無い板, 厚みの無い板の外接半径,
    反証が写した休止と判定する並進速度の閾値, 比較の許容差, 立方体, 立方体の外接半径, 試験の刻み幅, 静穏の閾値から求めた下限,
};
use super::motion::接触生成の余白を導く形の運動;
use crate::rigid_body::運動状態;

#[test]
fn 静止した二つの剛体では静穏の閾値から求めた下限が返る() {
    let 余白 = 上下の立方体の余白(運動状態::静止(), 運動状態::静止());
    let 期待する下限 = 静穏の閾値から求めた下限();
    assert!(
        (余白 - 期待する下限).abs() < 比較の許容差,
        "静止した対の余白{余白}が静穏の閾値から求めた下限{期待する下限}と違う"
    );
}

#[test]
fn 厚みの無い板が相手でも余白は静穏の閾値から求めた下限を下回らない() {
    let 余白 = 細分の運動から接触生成の余白を導く(
        &接触生成の余白を導く形の運動::静止した形から生成する(&立方体(0.5)),
        &接触生成の余白を導く形の運動::静止した形から生成する(&厚みの無い板(0.0)),
        試験の刻み幅(),
    )
    .unwrap()
    .値();
    let 期待する下限 = 二つの外接半径から静穏の下限を求める(立方体の外接半径, 厚みの無い板の外接半径);
    assert!(
        (余白 - 期待する下限).abs() < 比較の許容差,
        "厚み0の板を相手にした余白{余白}が静穏の閾値から求めた下限{期待する下限}と違う"
    );
}

// 判断18は島の各動的剛体へ |v| ≤ v_休止 を課すため、静穏な対の相対の並進速度は 2 v_休止 まで在りうる。
// その最も速い相対の並進を下限が覆っていないと、剛体の側が静穏と見なしている対の候補点が細分ごとに入れ替わる。
// 期待値は静止した対と同じ下限であり、この対の余白がそこから動かないことが、下限が 2 v_休止 を含むことを示す。
#[test]
fn 互いに逆向きへ休止の閾値で並進する対でも余白は静止した対と同じ下限のままである() {
    let 休止の閾値の速さ = 反証が写した休止と判定する並進速度の閾値;
    let 余白 = 上下の立方体の余白(上下に並進する運動状態(休止の閾値の速さ), 上下に並進する運動状態(-休止の閾値の速さ));
    let 期待する下限 = 静穏の閾値から求めた下限();
    assert!(
        (余白 - 期待する下限).abs() < 比較の許容差,
        "互いに逆向きへ休止の閾値で並進する対の余白{余白}が静止した対と同じ下限{期待する下限}と違う"
    );
}
