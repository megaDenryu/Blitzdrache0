//! 接触を解く品質の設定(判断19)。細分1本の中で位置の反復を何回回すかと、速度段階を何巡させるかの2つを持つ。
//! この2つを型で持つのは、どちらも隠れた定数にしてはならない量だからである。実行負荷で変えず、コンポジションルートが
//! 剛体の品質方針として注入する(判断19の規律)。細分数nは基本刻みの分割であり時間の規律の側が持つため、ここには入れない。
//! 値の由来は `_doc/計測/剛体の接触の摩擦と反発_2026-09-03.md` にあり、正本の判断19の実装の細目が根拠を述べる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」

use super::solver_quality_error::接触を解く品質の設定エラー;

/// 細分1本の中で接触を解く回数の設定。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 接触を解く品質の設定 {
    位置の反復回数: u32,
    速度段階の巡回数: u32,
}

impl 接触を解く品質の設定 {
    /// 2つの回数から作る。どちらも0は解かないことを意味するため拒む。
    pub fn 生成する(位置の反復回数: u32, 速度段階の巡回数: u32) -> Result<Self, 接触を解く品質の設定エラー> {
        if 位置の反復回数 == 0 {
            return Err(接触を解く品質の設定エラー::位置の反復回数が零);
        }
        if 速度段階の巡回数 == 0 {
            return Err(接触を解く品質の設定エラー::速度段階の巡回数が零);
        }
        Ok(Self {
            位置の反復回数,
            速度段階の巡回数,
        })
    }

    /// 細分1本の中で、全部の非貫通と接触点集合ごとの静止摩擦を回す回数。
    pub fn 位置の反復回数(&self) -> u32 {
        self.位置の反復回数
    }

    /// 細分1本の速度段階を巡らせる数。1巡目で動摩擦と反発を、2巡目からは反発だけを適用する。
    pub fn 速度段階の巡回数(&self) -> u32 {
        self.速度段階の巡回数
    }
}
