//! 接触島の検査(判断17)。
//! 離れた塔が別の島になること、静的な床を挟んだ箱が別の島になること、構築順序の決定性を検証する。

use super::super::contact_test_fixtures::{
    単一の材質の混合則, 台帳へ登録する, 接触に参加する剛体を作る, 試験の刻み幅, 静的世界の接触相手を作る
};
use super::super::stacked_box_fixture::上下の箱の接触点集合;
use super::island_builder::接触島の一覧を構築する;
use crate::contact::batch_builder::接触拘束のバッチの組み立て;
use crate::rigid_body::{剛体の台帳, 姿勢, 配置};
use crate::xpbd::コンプライアンス;
use blitz_math::{メートル, ワールド, 位置};

fn 位置(x: f32, y: f32, z: f32) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

#[test]
fn 離れた二つの箱の塔が別の島になる() {
    let mut 台帳 = 剛体の台帳::空();
    let 箱1 = 台帳へ登録する(&mut 台帳, 配置::生成する(位置(0.0, 0.0, 0.0), 姿勢::恒等()));
    let 箱2 = 台帳へ登録する(&mut 台帳, 配置::生成する(位置(0.0, 1.0, 0.0), 姿勢::恒等()));
    let 箱3 = 台帳へ登録する(&mut 台帳, 配置::生成する(位置(10.0, 0.0, 0.0), 姿勢::恒等()));
    let 箱4 = 台帳へ登録する(&mut 台帳, 配置::生成する(位置(10.0, 1.0, 0.0), 姿勢::恒等()));
    let 集合 = 上下の箱の接触点集合(姿勢::恒等());
    let 混合則 = 単一の材質の混合則();
    let mut 組み立て = 接触拘束のバッチの組み立て::生成する(&混合則, コンプライアンス::硬い(), 試験の刻み幅(), 2);
    let 参加者1 = 接触に参加する剛体を作る(箱1, 配置::生成する(位置(0.0, 0.0, 0.0), 姿勢::恒等()));
    let 参加者2 = 接触に参加する剛体を作る(箱2, 配置::生成する(位置(0.0, 1.0, 0.0), 姿勢::恒等()));
    let 参加者3 = 接触に参加する剛体を作る(箱3, 配置::生成する(位置(10.0, 0.0, 0.0), 姿勢::恒等()));
    let 参加者4 = 接触に参加する剛体を作る(箱4, 配置::生成する(位置(10.0, 1.0, 0.0), 姿勢::恒等()));
    let Ok(()) = 組み立て.剛体どうしの接触点集合を積む(&参加者1, &参加者2, &集合) else {
        panic!("接触点集合1-2の登録に失敗した");
    };
    let Ok(()) = 組み立て.剛体どうしの接触点集合を積む(&参加者3, &参加者4, &集合) else {
        panic!("接触点集合3-4の登録に失敗した");
    };
    let mut バッチ = 組み立て.二つのバッチを組み立てる();
    let 動的剛体一覧 = vec![箱1, 箱2, 箱3, 箱4];
    let 島一覧 = 接触島の一覧を構築する(&動的剛体一覧, &mut バッチ);
    assert_eq!(島一覧.len(), 2);
    assert_eq!(島一覧[0].含まれる動的剛体(), &[箱1, 箱2]);
    assert_eq!(島一覧[1].含まれる動的剛体(), &[箱3, 箱4]);
}

#[test]
