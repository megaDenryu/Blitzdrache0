    let mut 台帳 = 剛体の台帳::空();
    let 箱1 = 台帳へ登録する(&mut 台帳, 配置::生成する(位置(0.0, 1.0, 0.0), 姿勢::恒等()));
    let 箱2 = 台帳へ登録する(&mut 台帳, 配置::生成する(位置(5.0, 1.0, 0.0), 姿勢::恒等()));
    let 相手 = 静的世界の接触相手を作る(0);
    let 集合 = 上下の箱の接触点集合(姿勢::恒等());
