//! 接触島(判断17)。
//! 接触拘束で結ばれた動的剛体の連結成分であり、反復・休止と再開・並列化の論理単位である。
//! 島の順序は含まれる最小の剛体の識別子の昇順であり、島の中の拘束は鍵の昇順で解く。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断17: 接触島は動的剛体の連結成分であり、島の中の反復の順序は鍵の辞書式昇順である」

use crate::rigid_body::剛体の識別子;

use super::island_range::島の拘束の添字区間;

/// 接触拘束で結ばれた動的剛体の連結成分。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 接触島 {
    最小の剛体の識別子: 剛体の識別子,
    含まれる動的剛体: Vec<剛体の識別子>,
    剛体と静的世界の接触拘束の区間: 島の拘束の添字区間,
    剛体どうしの接触拘束の区間: 島の拘束の添字区間,
    剛体と静的世界の接触点集合の区間: 島の拘束の添字区間,
    剛体どうしの接触点集合の区間: 島の拘束の添字区間,
}

impl 接触島 {
    /// 最小の剛体識別子、含まれる動的剛体一覧、および各バッチ・接触点集合の区間から島を生成する。
    pub fn 生成する(
        最小の剛体の識別子: 剛体の識別子,
        含まれる動的剛体: Vec<剛体の識別子>,
        剛体と静的世界の接触拘束の区間: 島の拘束の添字区間,
        剛体どうしの接触拘束の区間: 島の拘束の添字区間,
        剛体と静的世界の接触点集合の区間: 島の拘束の添字区間,
        剛体どうしの接触点集合の区間: 島の拘束の添字区間,
    ) -> Self {
        Self {
            最小の剛体の識別子,
            含まれる動的剛体,
            剛体と静的世界の接触拘束の区間,
            剛体どうしの接触拘束の区間,
            剛体と静的世界の接触点集合の区間,
            剛体どうしの接触点集合の区間,
        }
    }

    pub fn 最小の剛体の識別子(&self) -> 剛体の識別子 {
        self.最小の剛体の識別子
    }

    pub fn 含まれる動的剛体(&self) -> &[剛体の識別子] {
        &self.含まれる動的剛体
    }

    pub fn 剛体と静的世界の接触拘束の区間(&self) -> 島の拘束の添字区間 {
        self.剛体と静的世界の接触拘束の区間
    }

    pub fn 剛体どうしの接触拘束の区間(&self) -> 島の拘束の添字区間 {
        self.剛体どうしの接触拘束の区間
    }

    pub fn 剛体と静的世界の接触点集合の区間(&self) -> 島の拘束の添字区間 {
        self.剛体と静的世界の接触点集合の区間
    }

    pub fn 剛体どうしの接触点集合の区間(&self) -> 島の拘束の添字区間 {
        self.剛体どうしの接触点集合の区間
    }

    /// 指定した剛体がこの島に含まれる動的剛体であるか。
    pub fn 動的剛体を含むか(&self, 識別子: 剛体の識別子) -> bool {
        self.含まれる動的剛体.binary_search(&識別子).is_ok()
    }
}
