//! 接触島の一覧を構築する工程(判断17)。
//! 動的剛体の連結成分を求め、接触拘束のバッチを島順かつ鍵昇順へ並べ替え、添字区間を持つ接触島の一覧を返す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断17: 接触島は動的剛体の連結成分であり、島の中の反復の順序は鍵の辞書式昇順である」

use std::collections::BTreeMap;

use crate::rigid_body::剛体の識別子;

use super::super::contact_batches::接触拘束の二つのバッチ;
use super::contact_island::接触島;
use super::island_reorder::{剛体どうしの接触を島順に並べ直す, 静的世界の接触を島順に並べ直す};
use super::island_union_find::動的剛体の素集合;

/// 接触拘束のバッチと動的剛体の一覧から、接触島の一覧を構築し、バッチを島順へ並べ直す。
pub fn 接触島の一覧を構築する(
    動的剛体一覧: &[剛体の識別子], バッチ: &mut 接触拘束の二つのバッチ
) -> Vec<接触島> {
    let mut 素集合 = 動的剛体の素集合::動的剛体一覧から生成する(動的剛体一覧);
    let ペア一覧: Vec<_> = バッチ
        .剛体どうしの接触拘束()
        .iter()
        .map(|k| (k.履歴の鍵().小さい方の剛体(), k.履歴の鍵().大きい方の剛体()))
        .collect();
    for &(a, b) in &ペア一覧 {
        素集合.併合する(a, b);
    }
    let 島ごとの剛体たち = 素集合.島ごとの動的剛体一覧を構築する();
    let mut 剛体から島番号 = BTreeMap::new();
    for (島番号, 剛体一覧) in 島ごとの剛体たち.iter().enumerate() {
        for &剛体 in 剛体一覧 {
            剛体から島番号.insert(剛体, 島番号);
        }
    }
    let 静的集合ごとの島番号: Vec<Option<usize>> = (0..バッチ.剛体と静的世界の接触点集合の数())
        .map(|集合番号| {
            let 拘束一覧 = バッチ.剛体と静的世界の接触点集合を反復のために借りる(集合番号);
            拘束一覧.first().and_then(|拘束| 剛体から島番号.get(&拘束.引数().剛体).copied())
        })
        .collect();
    let 剛体間集合ごとの島番号: Vec<Option<usize>> = (0..バッチ.剛体どうしの接触点集合の数())
        .map(|集合番号| {
            let 拘束一覧 = バッチ.剛体どうしの接触点集合を反復のために借りる(集合番号);
            拘束一覧.first().and_then(|拘束| {
                let 鍵 = 拘束.履歴の鍵();
                剛体から島番号
                    .get(&鍵.小さい方の剛体())
                    .copied()
                    .or_else(|| 剛体から島番号.get(&鍵.大きい方の剛体()).copied())
            })
        })
        .collect();
    let 島の数 = 島ごとの剛体たち.len();
    let (新静的拘束, 新静的範囲, 静的拘束区間, 静的集合区間) = 静的世界の接触を島順に並べ直す(
        バッチ.剛体と静的世界の接触拘束(),
        バッチ.剛体と静的世界の接触点集合の範囲(),
        &静的集合ごとの島番号,
        島の数,
    );
    let (新剛体間拘束, 新剛体間範囲, 剛体間拘束区間, 剛体間集合区間) = 剛体どうしの接触を島順に並べ直す(
        バッチ.剛体どうしの接触拘束(),
        バッチ.剛体どうしの接触点集合の範囲(),
        &剛体間集合ごとの島番号,
        島の数,
    );
    *バッチ = 接触拘束の二つのバッチ::積み終えた一覧から組む(新剛体間拘束, 新静的拘束, 新剛体間範囲, 新静的範囲);
    let mut 島一覧 = Vec::with_capacity(島の数);
    for (島番号, 含まれる動的剛体) in 島ごとの剛体たち.into_iter().enumerate() {
        let Some(&最小識別子) = 含まれる動的剛体.first() else {
            continue;
        };
        島一覧.push(接触島::生成する(
            最小識別子,
            含まれる動的剛体,
            静的拘束区間[島番号],
            剛体間拘束区間[島番号],
            静的集合区間[島番号],
            剛体間集合区間[島番号],
        ));
    }
    島一覧
}
