//! 直前の細分が組んだ接触島の分割(判断17・18)。
//! 休止した島の剛体どうしは接触点集合を作らないため、その細分のバッチだけからは休止した島の形を復元できない。
//! 再開の契機を島の全部へ広げる工程と、島を組み直す工程がこの分割を読む。
//! 注意: 置き換えは細分の末で行う。契機を受ける工程が読むのは1つ前の細分の分割である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use crate::contact::rest::剛体を起こす;
use crate::rigid_body::{休止から起きた理由, 剛体, 剛体の識別子};

use super::contact_island::接触島;
use super::island_union_find::動的剛体の素集合;

/// 直前の細分が組んだ接触島の分割。
pub struct 直前の細分の接触島の一覧 {
    島一覧: Vec<接触島>,
}

impl 直前の細分の接触島の一覧 {
    /// まだ1本も細分を回していない工程が持つ、空の分割。
    pub fn 空から始める() -> Self {
        Self { 島一覧: Vec::new() }
    }

    pub fn 島一覧(&self) -> &[接触島] {
        &self.島一覧
    }

    /// 細分の末で、その細分が組み直した分割へ入れ替える。
    pub fn 組み直した島で置き換える(&mut self, 島一覧: Vec<接触島>) {
        self.島一覧 = 島一覧;
    }

    /// 再開の契機が指す剛体を含む島を丸ごと起こし、島の全部の剛体へ同じ理由を記録する(判断18)。
    /// まだどの島にも現れていない剛体は、その1体だけを起こす。登録された直後の剛体がこれに当たり、その剛体は起きているため理由は残らない。
    pub fn 契機を受けて島ごと起こす(
        &self, 識別子: 剛体の識別子, 理由: 休止から起きた理由, 剛体一覧: &mut [剛体]
    ) {
        for 島 in &self.島一覧 {
            if 島.動的剛体を含むか(識別子) {
                島.起こす(剛体一覧, 理由);
                return;
            }
        }
        剛体を起こす(識別子, 剛体一覧, 理由);
    }

    /// 休止したままの剛体どうしを、直前の分割のとおりに結び直す(判断18)。
    /// 休止している剛体どうしの対は接触点集合を作らないため、これを行わないと休止した島が細分ごとに1体ずつの島へ割れ、
    /// 再開の契機が島の一部にしか届かなくなる。
    pub(super) fn 休止したままの剛体を素集合へ結び直す(&self, 素集合: &mut 動的剛体の素集合, 剛体一覧: &[剛体]) {
        for 島 in &self.島一覧 {
            let mut 結び先: Option<剛体の識別子> = None;
            for &識別子 in 島.含まれる動的剛体() {
                if !剛体一覧.get(識別子.配列添字()).is_some_and(|剛体| 剛体.実行状態().休止しているか()) {
                    continue;
                }
                match 結び先 {
                    None => 結び先 = Some(識別子),
                    Some(先) => 素集合.併合する(先, 識別子),
                }
            }
        }
    }
}
