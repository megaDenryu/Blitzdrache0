//! 混合則が接触物性を決める規則の試験(判断15)。担当するのは3つの性質を固定することである。既定則が摩擦の相乗平均と
//! 反発の最大値であって可換であること、材質対の上書きが既定則より優先されて順を入れ替えても同じ値になること、
//! 登録されていない材質が黙って既定の物性で埋まらず型付きエラーになることである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断15: 接触物性は両表面の物性から混合則で決め、既定則と材質対の上書き表を持つ」

#![allow(clippy::unwrap_used)]

use super::material_id::材質の識別子;
use super::property_error::接触物性エラー;
use super::property_test_fixtures::{
    接触物性を作る, 見本の混合則を組み立てる, 見本を登録した組み立てを作る, 見本一覧
};

#[test]
fn 既定則は摩擦の相乗平均と反発の最大値であり可換である() {
    let 混合則 = 見本の混合則を組み立てる();
    for (第1の番号, 第1の静止, 第1の動, 第1の反発) in 見本一覧 {
        for (第2の番号, 第2の静止, 第2の動, 第2の反発) in 見本一覧 {
            let 第1 = 材質の識別子::生成する(第1の番号);
            let 第2 = 材質の識別子::生成する(第2の番号);
            let 物性 = 混合則.接触物性を求める(第1, 第2).unwrap();
            assert!((物性.静止摩擦係数().値() - (第1の静止 * 第2の静止).sqrt()).abs() < 1.0e-6);
            assert!((物性.動摩擦係数().値() - (第1の動 * 第2の動).sqrt()).abs() < 1.0e-6);
            assert_eq!(物性.反発係数().値(), 第1の反発.max(第2の反発));
            assert_eq!(物性, 混合則.接触物性を求める(第2, 第1).unwrap());
        }
    }
}

#[test]
fn 材質対の上書きは既定則より優先され順を入れ替えても同じである() {
    let mut 組み立て = 見本を登録した組み立てを作る();
    let (木, 氷, ゴム) = (材質の識別子::生成する(0), 材質の識別子::生成する(1), 材質の識別子::生成する(2));
    let 上書き = 接触物性を作る(0.9, 0.8, 0.05);
    組み立て.材質対の上書きを登録する(氷, 木, 上書き).unwrap();
    let 混合則 = 組み立て.組み立てる().unwrap();
    assert_eq!(混合則.接触物性を求める(木, 氷).unwrap(), 上書き);
    assert_eq!(混合則.接触物性を求める(氷, 木).unwrap(), 上書き);
    let 上書きの無い対 = 混合則.接触物性を求める(木, ゴム).unwrap();
    assert!((上書きの無い対.静止摩擦係数().値() - (0.6f32 * 1.2).sqrt()).abs() < 1.0e-6);
}

#[test]
fn 登録されていない材質の接触物性を型付きエラーで拒む() {
    assert_eq!(
        見本の混合則を組み立てる().接触物性を求める(材質の識別子::生成する(0), 材質の識別子::生成する(9)),
        Err(接触物性エラー::材質の表面物性が未登録 { 材質の識別子: 9 })
    );
}
