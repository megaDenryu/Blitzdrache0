//! 接触物性が法線のラグランジュ乗数から導く2つの限界(判断13・判断14)。値の定義と値域の検査から分けているのは、
//! この2つが接触物性の欄でなく、その細分の法線反力と組み合わせて初めて決まる量だからである。触れるのは摩擦の2つの係数だけである。
//!   クーロン円錐の半径 μ_s λ_n [kg·m]: 静止摩擦が保持できる接線の乗数の大きさの上限である
//!   動摩擦の衝撃の上限 μ_d λ_n ÷ h [N·s]: 法線反力 f_n = λ_n ÷ h² が細分の時間 h の間に与えうる摩擦の衝撃である
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

use blitz_math::ニュートン秒;

use super::contact_property::接触物性;
use crate::xpbd::{ラグランジュ乗数, 刻み幅};

impl 接触物性 {
    /// 静止摩擦のクーロン円錐の半径 μ_s λ_n。接線の乗数の大きさがこれを超えたら滑走中である。
    pub fn 静止摩擦の円錐の半径を求める(
        &self, 法線のラグランジュ乗数: ラグランジュ乗数
    ) -> ラグランジュ乗数 {
        self.静止摩擦係数().法線の乗数へ掛けた接線の乗数の限界(法線のラグランジュ乗数)
    }

    /// 動摩擦が1細分に与えうる衝撃の上限 μ_d λ_n ÷ h。速度段階はこれと接線の相対速度を零にする衝撃の小さい方を採る。
    pub fn 動摩擦の衝撃の上限を求める(
        &self, 法線のラグランジュ乗数: ラグランジュ乗数, 刻み幅: 刻み幅
    ) -> ニュートン秒 {
        self.動摩擦係数()
            .法線の乗数へ掛けた接線の乗数の限界(法線のラグランジュ乗数)
            .キログラムメートル()
            / 刻み幅.秒()
    }
}
