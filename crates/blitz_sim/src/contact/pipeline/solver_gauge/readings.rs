//! 解法の計器が数えたものを読む口(判断12・判断13。試験の構成の専用)。計器そのもの(`solver_gauge.rs`)から分けているのは、
//! あちらが数える工程(どの結末をどの欄へ足すか)であり、こちらが溜まった値を計器の外へ出す工程だからである。
//! 触れるのは数えの欄だけであり、当て方も連立方程式も読まない。読む口のうち4つは読んだ値を零に戻す。区切りごとに
//! 読む計器が、前の区切りの分を二重に数えないためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::super::acceptance_breach_reading::受理の破れの読み取り;
use super::super::acceptance_tally::受理の破れの数え;
use super::unsolved_tally::解けなかった結末の数え;
use super::解法の計器;
use crate::contact::normal_tangential_system::{単精度の解の内訳, 混合連立の受理の結果, 部分集合を解いた回数};

impl 解法の計器 {
    /// 受理の判定が破られた回数を契約ごとに数えたもの。
    pub(in crate::contact::pipeline) fn 受理の破れ(&self) -> 受理の破れの数え {
        self.受理の破れ.get()
    }

    /// 数えた順の受理の結末を全部読んで空にする。診断の計器が刻みごとに読む口である。
    pub(in crate::contact::pipeline) fn 受理の判定の履歴を読んで空にする(
        &self,
    ) -> Vec<(混合連立の受理の結果, Option<受理の破れの読み取り>)> {
        std::mem::take(&mut *self.受理の判定の履歴.borrow_mut())
    }

    /// 累計を読んで零に戻す。計器が区切りごとに読む口である。区切りを置かずに最後で1度読めば全体の累計になる。
    pub(in crate::contact::pipeline) fn 解いた回数の累計を読んで零に戻す(&self) -> 部分集合を解いた回数 {
        self.解いた回数の累計.replace(部分集合を解いた回数::零())
    }

    /// 粘着の候補が解けずに退避した延べ数と、そのうち表現の精度が不足した延べ数。
    pub(in crate::contact::pipeline) fn 解けなかった結末(&self) -> 解けなかった結末の数え {
        self.解けなかった結末.get()
    }

    /// 定まった解の内訳を数える印を立て、それまでに溜まった内訳を取り出して空にする。段階A2の計測3と段階A3の計測1の計器が読む。
    pub(in crate::contact::pipeline) fn 定まった解の内訳を数え始めて溜まった分を読む(&self) -> Vec<単精度の解の内訳> {
        self.定まった解の内訳の数え.borrow_mut().数え始めて溜まった分を読む()
    }

    /// 受理の判定を通った連立の錨からの接線変位の長さの最大を読んで零に戻す。接線の雑音の床を測る計器が刻みごとに読む。
    pub(in crate::contact::pipeline) fn 接線変位の長さの最大を読んで零に戻す(&self) -> f32 {
        self.接線変位の長さの最大.replace(0.0)
    }
}
