//! 混合連立の求解ごとに、定まった解の内訳を溜める数え(Issue #103の段階A2の計測3と段階A3の計測1。試験と計器の専用)。
//! 解法の計器(`solver_gauge`)から分けているのは、こちらが内訳だけを溜める受け皿であり、あちらが適用規則と解いた回数と
//! 受理の破れを束ねる型だからである。内訳から何を読むか(偽の固有値の下限に対する分布・固有値を最大で割った相対値の
//! 広がり)は、溜めた並びを受け取る計器の側が決める。溜める側が読み方を選ぶと、読み方が増えるたびに受け皿が増える。
//! 数えるかどうかの印を並びと同じ型が持つのは、この2つが同時に立ち同時に空になるためである。印を持つのは、
//! 1件を数えるたびに勝った有効集合の探索をもう一度走らせるためであり、印の無い試験の実行が遅くならないようにする。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use crate::contact::normal_tangential_system::{単精度の解の内訳, 接触点集合の法線と接線の連立};

/// 求解ごとの定まった解の内訳を、数える印が立っているあいだだけ溜める受け皿。
pub(super) struct 定まった解の内訳の数え {
    数えるか: bool,
    溜まった内訳: Vec<単精度の解の内訳>,
}

impl 定まった解の内訳の数え {
    pub(super) fn 零から始める() -> Self {
        Self {
            数えるか: false,
            溜まった内訳: Vec::new(),
        }
    }

    /// 連立1つの内訳を数える。印が立っていないか、相補条件を満たす有効集合が定まらなければ何もしない。
    pub(super) fn 一件を数える(&mut self, 連立: &接触点集合の法線と接線の連立) {
        if !self.数えるか {
            return;
        }
        let Some(内訳) = 連立.定まった解の内訳を読む() else {
            return;
        };
        self.溜まった内訳.push(内訳);
    }

    /// 数える印を立て、それまでに溜まった内訳を取り出して空にする。計器が刻みごとに呼ぶ唯一の口である。
    pub(super) fn 数え始めて溜まった分を読む(&mut self) -> Vec<単精度の解の内訳> {
        self.数えるか = true;
        std::mem::take(&mut self.溜まった内訳)
    }
}
