//! 粘着の候補が解けずに退避した結末の数え(判断12・判断13。試験の構成の専用)。計器そのもの(`solver_gauge.rs`)から
//! 分けているのは、この2つの数が同じ地点で一緒に増えるためである。表現の精度が不足した結末は、解けなかった結末の
//! 一部でもあるから、片方だけを足す呼び出しは起こり得ない。2つを別のフィールドで持つと、呼び出し側が「両方へ足す」
//! という規律を毎回守ることになる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use crate::contact::normal_tangential_system::相補条件を満たす有効集合を探した結末;

/// 粘着の候補が解けずに退避した延べ数と、そのうち表現の精度が不足した延べ数。
#[derive(Debug, Clone, Copy)]
pub(in crate::contact::pipeline) struct 解けなかった結末の数え {
    延べ数: usize,
    表現の精度が不足した延べ数: usize,
}

impl 解けなかった結末の数え {
    pub(super) fn 零から始める() -> Self {
        Self {
            延べ数: 0,
            表現の精度が不足した延べ数: 0,
        }
    }

    /// 有効集合の探索の結末を1件数える。定まった結末は何も足さない。
    pub(super) fn 探索の結末を一件数える(&mut self, 結末: &相補条件を満たす有効集合を探した結末) {
        match 結末 {
            相補条件を満たす有効集合を探した結末::有効集合が定まった { .. } => {}
            相補条件を満たす有効集合を探した結末::相補条件を満たす有効集合が無い => self.延べ数 += 1,
            相補条件を満たす有効集合を探した結末::表現の精度が不足した => {
                self.延べ数 += 1;
                self.表現の精度が不足した延べ数 += 1;
            }
        }
    }

    /// 受理の判定が数値の契約を破って退避した1件を数える。表現の精度の不足には数えない。
    pub(super) fn 受理の破れを一件数える(&mut self) {
        self.延べ数 += 1;
    }

    pub(in crate::contact::pipeline) fn 延べ数(&self) -> usize {
        self.延べ数
    }

    pub(in crate::contact::pipeline) fn 表現の精度が不足した延べ数(&self) -> usize {
        self.表現の精度が不足した延べ数
    }
}
