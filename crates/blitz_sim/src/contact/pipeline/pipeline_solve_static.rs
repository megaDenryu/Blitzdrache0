//! 剛体と静的世界の接触点集合の位置反復(判断12・13)。
//! 接触点集合1つの法線の行と接線の行を1回の混合連立として同時に解き、更新後の乗数でクーロン円錐を1度だけ判定し、
//! 内側なら配置と法線の乗数と接線の乗数を一括で確定する。超えたときと解けなかったときは、同じ開始の配置から
//! 法線だけの連立を解き直し、その法線の解だけを確定して集合を滑走中へ移す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12」「判断13」。

use super::pipeline_error::接触の工程エラー;
use super::pipeline_solver::接触の解法ソルバー;
use super::pipeline_static_rows::{仮の乗数の集まりを求める, 法線だけを同時に解く, 法線と接線の連立を組む};
use super::substep_predict::細分の動的剛体;
use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::normal_tangential_system::相補条件を満たす有効集合を探した結末;
use crate::contact::static_friction::接触点集合の仮の乗数の集まり;
use crate::rigid_body::{剛体, 剛体エラー};
use crate::rigid_xpbd::{予測の状態, 姿勢自由度の参加者};

impl 接触の解法ソルバー {
    pub(super) fn 静的世界の接触点集合を一回反復する(
        &self,
        集合: &mut [剛体と静的世界の接触拘束],
        動的剛体一覧: &mut [細分の動的剛体],
        剛体一覧: &[剛体],
    ) -> Result<(), 接触の工程エラー> {
        let Some(先頭) = 集合.first() else {
            return Ok(());
        };
        let (識別子, 接触物性, 滑走中か) = (先頭.引数().剛体, 先頭.引数().接触物性, 先頭.静止摩擦の解の状態().滑走中か());
        let 台帳剛体 = 剛体一覧.get(識別子.配列添字()).ok_or(剛体エラー::剛体が登録されていない { 識別子 })?;
        let Some(剛体) = 動的剛体一覧.iter_mut().find(|剛体| 剛体.識別子 == 識別子) else {
            return Ok(());
        };
        if 滑走中か {
            剛体.予測 = 法線だけを同時に解く(集合, 剛体.予測, 台帳剛体);
            return Ok(());
        }
        let 参加者 = 姿勢自由度の参加者::動的(*剛体.予測.配置(), 台帳剛体.質量特性());
        let (連立, 点を入れた結果) = 法線と接線の連立を組む(集合, &参加者);
        let 相補条件を満たす有効集合を探した結末::有効集合が定まった(同時解) = 連立.相補条件を満たす有効集合で同時に解く()
        else {
            剛体.予測 = 法線だけを同時に解く(集合, 剛体.予測, 台帳剛体);
            return Ok(());
        };
        let 仮の乗数 = 仮の乗数の集まりを求める(集合, &連立, &同時解, &点を入れた結果);
        if !仮の乗数.円錐の内側か(接触物性) {
            剛体.予測 = 粘着の候補を捨てて滑走中にする(集合, 剛体.予測, 台帳剛体, &仮の乗数);
            return Ok(());
        }
        for (添字, 拘束) in 集合.iter_mut().enumerate() {
            拘束.法線と接線の連立の法線の乗数の増分を取り込む(&参加者, 同時解.一点の法線の乗数の増分(添字));
            拘束.静止摩擦の仮の乗数を確定する(仮の乗数.一点の仮の接線の乗数(添字).確定する接線の乗数());
        }
        剛体.予測 = 剛体.予測.補正を適用する(&連立.第1の参加者への補正の合計(&同時解));
        Ok(())
    }
}

// 円錐を超えた粘着の候補を全部捨て、同じ開始の配置から法線だけの連立を解いて集合を滑走中へ移す。
// 錨を置き直す先は、法線だけの連立を解き終えた配置の接触点である。解く前の配置へ置くと、次の細分がその遅れと
// 自分の滑りを合わせて戻すことになり、一度滑り出した集合が二度と保持へ戻れない。
fn 粘着の候補を捨てて滑走中にする(
    集合: &mut [剛体と静的世界の接触拘束],
    射影の前の予測: 予測の状態,
    台帳剛体: &剛体,
    仮の乗数: &接触点集合の仮の乗数の集まり,
) -> 予測の状態 {
    let 法線を解いた予測 = 法線だけを同時に解く(集合, 射影の前の予測, 台帳剛体);
    let 参加者 = 姿勢自由度の参加者::動的(*法線を解いた予測.配置(), 台帳剛体.質量特性());
    for (添字, 拘束) in 集合.iter_mut().enumerate() {
        拘束.接触点集合が滑走中になったと印す(&参加者);
        if 仮の乗数.一点の仮の接線の乗数(添字).集合が円錐を超えても解放するか() {
            拘束.静止摩擦の接線の乗数を零へ解放する();
        }
    }
    法線を解いた予測
}
