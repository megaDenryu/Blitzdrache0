//! 坂の上の2段の箱の接触の対ごとに、細分の終わりの法線と接線の乗数の合計とクーロン円錐の比を綴る一次計測の計器
//! (親の2026-09-12の指示。判断13の反証(4)(e)の原因の切り分け)。合否は判定しない。
//! 対は、床と下の箱の対と、下の箱と上の箱の対の2つである。対ごとに綴るのは、法線の乗数の合計・接線の乗数の大きさの
//! 合計・その比・接触点の数・滑走中と印された点の数である。円錐を超えた細分では解法が粘着の候補を捨てて集合を滑走中へ
//! 移すため、滑走中の点の数が「その対のその細分で円錐を超えた」ことの印である。接触点が1つも無い細分は、その対の行が
//! 出ない(上の箱が下の箱から離れた細分である)。
//! 静止の解が要求する乗数は `静止の解が要求する乗数` が重力と細分の刻み幅から導き、測った合計と並べて綴る。
//! 場面は `stacked_slope_fixture` が組む。
//! 実行は `cargo test -p blitz_sim --release 一次計測_坂の上の二段の箱 -- --ignored --nocapture` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use std::collections::BTreeMap;

use super::stacked_slope_cone_tally::{接触の対の乗数の集計, 静止の解が要求する乗数};
use super::stacked_slope_fixture::坂の上の二段の箱の場面;
use crate::contact::friction_coefficient::摩擦係数;
use crate::contact::normal_tangential_system::{
    接線の行への許容差の適用規則, 解けたと見なす許容差の倍率, 試験の許容差の適用規則
};

const 傾きの正接: f32 = 0.55;
const 静止摩擦係数の値: f32 = 0.6;
const 綴る刻み: &[usize] = &[0, 1, 100];
const 走らせる刻み数: usize = 101;

fn 一つの適用規則を綴る(見出し: &str, 適用規則: 試験の許容差の適用規則) {
    let Ok(摩擦) = 摩擦係数::生成する(静止摩擦係数の値) else {
        panic!("摩擦係数を作れない");
    };
    let mut 場面 = 坂の上の二段の箱の場面::生成する(傾きの正接, 摩擦);
    場面.工程.解法.計器.許容差の適用規則を差し替える(適用規則);
    println!("[{見出し}]");
    for 刻み in 0..走らせる刻み数 {
        let Ok(細分ごと) = 場面.工程.一刻み進めて細分ごとのバッチを返す(&mut 場面.台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        if !綴る刻み.contains(&刻み) {
            continue;
        }
        for (細分の番号, バッチ) in 細分ごと.iter().enumerate() {
            let mut 対ごと: BTreeMap<(usize, usize), 接触の対の乗数の集計> = BTreeMap::new();
            for 拘束 in バッチ.剛体どうしの接触拘束() {
                対ごと.entry(接触の対の乗数の集計::対の鍵(拘束)).or_default().一点を足す(拘束);
            }
            let 綴り: Vec<String> = 対ごと.iter().map(|(鍵, 集計)| format!("対{鍵:?}{{{}}}", 集計.綴り())).collect();
            println!("  刻み{刻み} 細分{細分の番号} {}", 綴り.join(" "));
        }
    }
}

