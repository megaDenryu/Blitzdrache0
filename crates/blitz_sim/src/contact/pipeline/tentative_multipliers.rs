//! 混合連立を解いた増分から、接触点集合の仮の乗数の集まりを組む工程(判断12・13)。
//! 剛体どうしの接触点集合と剛体と静的世界の接触点集合で、この工程の中身は1行も違わない。読むのは接触点1つの
//! 静止摩擦の解の状態と法線のラグランジュ乗数の2つだけであり、参加者が1つか2つかはここでは効かないためである。
//! 2つの経路へ同じ本文を写すと、判断13の定式を変える日に直す場所が2つになる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12」「判断13」。

use blitz_collision::contact_set::接触点の上限;

use crate::contact::body_body_contact::剛体と剛体の接触拘束;
use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::normal_tangential_system::{接触点集合の法線と接線の同時解, 接触点集合の法線と接線の連立};
use crate::contact::static_friction::{
    接触点の仮の接線の乗数, 接触点集合の仮の乗数の集まり, 静止摩擦の一細分の解の状態, 静止摩擦の連立へ点を入れた結果,
};
use crate::xpbd::ラグランジュ乗数;

/// 仮の乗数の集まりを組むために接触点1つから読む2つの値。参加者の数はこの工程に関わらない。
pub(super) trait 仮の乗数を組める接触点 {
    fn 静止摩擦の解の状態(&self) -> 静止摩擦の一細分の解の状態;
    fn 法線のラグランジュ乗数(&self) -> ラグランジュ乗数;
}

impl 仮の乗数を組める接触点 for 剛体と剛体の接触拘束 {
    fn 静止摩擦の解の状態(&self) -> 静止摩擦の一細分の解の状態 {
        剛体と剛体の接触拘束::静止摩擦の解の状態(self)
    }

    fn 法線のラグランジュ乗数(&self) -> ラグランジュ乗数 {
        剛体と剛体の接触拘束::法線のラグランジュ乗数(self)
    }
}

impl 仮の乗数を組める接触点 for 剛体と静的世界の接触拘束 {
    fn 静止摩擦の解の状態(&self) -> 静止摩擦の一細分の解の状態 {
        剛体と静的世界の接触拘束::静止摩擦の解の状態(self)
    }

    fn 法線のラグランジュ乗数(&self) -> ラグランジュ乗数 {
        剛体と静的世界の接触拘束::法線のラグランジュ乗数(self)
    }
}

/// 解いた増分から点ごとの仮の接線の乗数と円錐の判定の集計を組む。法線の有効集合から外れた点は法線反力が無い点として扱う。
pub(super) fn 仮の乗数の集まりを求める<接触点: 仮の乗数を組める接触点>(
    集合: &[接触点],
    連立: &接触点集合の法線と接線の連立,
    同時解: &接触点集合の法線と接線の同時解,
    点を入れた結果: &[静止摩擦の連立へ点を入れた結果; 接触点の上限],
) -> 接触点集合の仮の乗数の集まり {
    let mut 仮の乗数 = 接触点集合の仮の乗数の集まり::空から始める();
    for (添字, 拘束) in 集合.iter().enumerate() {
        let 点の結果 = if 同時解.一点の法線の行が有効か(添字) {
            点を入れた結果[添字]
        } else {
            静止摩擦の連立へ点を入れた結果::法線反力が無い
        };
        仮の乗数.一点を足す(
            添字,
            接触点の仮の接線の乗数::積んだ行の向きと乗数の増分から決める(
                点の結果,
                拘束.静止摩擦の解の状態(),
                連立.接線の一行を読む(添字).map(|一行| 一行.接線の向き()),
                同時解.一点の接線の乗数の増分(添字),
            ),
            拘束.法線のラグランジュ乗数() + 同時解.一点の法線の乗数の増分(添字),
        );
    }
    仮の乗数
}
