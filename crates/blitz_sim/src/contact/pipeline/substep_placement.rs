//! 細分の予測が作る、接触点集合の生成へ渡す配置(判断11)。
//! 剛体1つの識別子と、この細分で接触点集合を作る配置と、その形の軸ごとの半分の長さと、この細分の開始時点の運動状態を1つの値として持つ。
//! 4つを別々の並びで持ち回らないのは、4つが常に揃って渡され、揃っていない組み合わせが接触点集合の生成にとって意味を持たないためである。
//! 運動状態を持つのは、接触生成の余白がこの細分の運動から導かれるためである(判断11の実装の細目)。
//! 衝突数学層へ渡す直方体はここに持たず、問い合わせごとに衝突の問い合わせの基準原点に相対な形として組む(判断3)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断3」「判断11」。

use std::collections::BTreeMap;

use blitz_collision::shape::直方体の軸ごとの半分の長さ;

use super::pipeline_error::接触の工程エラー;
use super::pipeline_space::接触の空間と世界;
use super::substep_predict::細分の動的剛体;
use crate::contact::contacting_body::接触に参加する剛体;
use crate::contact::generation_margin::接触生成の余白を導く形の運動;
use crate::contact::query_origin::衝突の問い合わせの基準原点;
use crate::rigid_body::{剛体の識別子, 運動状態, 配置};

pub(super) struct 接触点集合を作る配置 {
    pub(super) 識別子: 剛体の識別子,
    配置: 配置,
    半分の長さ: 直方体の軸ごとの半分の長さ,
    細分の開始時点の運動状態: 運動状態,
}

impl 接触点集合を作る配置 {
    /// 自分の粗い位置を衝突の問い合わせの基準原点にした、接触拘束の生成に参加する剛体。
    pub(super) fn 参加者を組む(&self, 空間: &接触の空間と世界) -> Result<接触に参加する剛体, 接触の工程エラー> {
        Ok(接触に参加する剛体::生成する(
            self.識別子,
            self.配置,
            空間.材質を参照する(self.識別子)?,
            空間.形の最小の厚みを求める(self.識別子)?,
            衝突の問い合わせの基準原点::剛体の粗い位置から選ぶ(&self.配置),
        ))
    }

    pub(super) fn 半分の長さ(&self) -> 直方体の軸ごとの半分の長さ {
        self.半分の長さ
    }

    /// 接触生成の余白の導出がこの形について読む運動(判断11)。座標の刻みの根拠になる原点からの長さは世界の座標で数える。
    pub(super) fn 余白を導く形の運動を組む(&self) -> Result<接触生成の余白を導く形の運動, 接触の工程エラー> {
        let 基準原点 = 衝突の問い合わせの基準原点::剛体の粗い位置から選ぶ(&self.配置);
        let 直方体 = 基準原点.剛体の相対の直方体を組む(&self.配置, self.半分の長さ)?;
        Ok(接触生成の余白を導く形の運動::世界に置いた形から生成する(
            基準原点.相対の位置を世界の位置として読む(直方体.中心()),
            &直方体,
            self.細分の開始時点の運動状態,
        ))
    }
}

/// 細分1本の予測の直前に、剛体がどの配置に居たかの一覧。接触が始まった接触点の静止摩擦の錨をここへ置く(判断13)。
pub(super) struct 細分の予測の前の配置一覧 {
    配置一覧: BTreeMap<剛体の識別子, 配置>,
}

impl 細分の予測の前の配置一覧 {
    /// この剛体が予測の直前に居た配置。登録されていない剛体には答えを持たない。
    pub(super) fn 配置を参照する(&self, 識別子: 剛体の識別子) -> Option<&配置> {
        self.配置一覧.get(&識別子)
    }
}

/// 細分1本の予測が終わった時点の、解く対象の剛体と、接触点集合の生成へ渡す配置の一覧と、予測の前の配置の一覧。
pub(super) struct 細分の予測の結果 {
    pub(super) 動的剛体一覧: Vec<細分の動的剛体>,
    pub(super) 接触点集合を作る配置一覧: Vec<接触点集合を作る配置>,
    pub(super) 予測の前の配置一覧: 細分の予測の前の配置一覧,
}

impl 細分の予測の結果 {
    pub(super) fn 空から始める() -> Self {
        Self {
            動的剛体一覧: Vec::new(),
            接触点集合を作る配置一覧: Vec::new(),
            予測の前の配置一覧: 細分の予測の前の配置一覧 {
                配置一覧: BTreeMap::new()
            },
        }
    }

    /// 予測しない剛体(静的・運動学的・休止中)を足す。この細分で動かないため、予測の前の配置はいまの配置である。
    /// 運動学的剛体は刻みの境目で配置が変わるため、この細分で配置が動かなくても持っている速度をそのまま受け取る。
    pub(super) fn 動かない剛体を足す(
        &mut self,
        識別子: 剛体の識別子,
        配置: 配置,
        半分の長さ: 直方体の軸ごとの半分の長さ,
        運動状態: 運動状態,
    ) {
        self.接触点集合を作る配置一覧.push(接触点集合を作る配置 {
            識別子,
            配置,
            半分の長さ,
            細分の開始時点の運動状態: 運動状態,
        });
        self.予測の前の配置一覧.配置一覧.insert(識別子, 配置);
    }

    pub(super) fn 予測した剛体を足す(
        &mut self,
        予測した剛体: 細分の動的剛体,
        半分の長さ: 直方体の軸ごとの半分の長さ,
        細分の開始時点の運動状態: 運動状態,
    ) {
        self.接触点集合を作る配置一覧.push(接触点集合を作る配置 {
            識別子: 予測した剛体.識別子,
            配置: *予測した剛体.予測.配置(),
            半分の長さ,
            細分の開始時点の運動状態,
        });
        self.予測の前の配置一覧
            .配置一覧
            .insert(予測した剛体.識別子, 予測した剛体.前の状態.保存した配置());
        self.動的剛体一覧.push(予測した剛体);
    }
}
