//! 細分の予測が作る、接触点集合の生成へ渡す配置(判断11)。
//! 剛体1つの識別子と、この細分で接触点集合を作る配置と、その配置での直方体を1つの値として持つ。
//! 3つを別々の並びで持ち回らないのは、3つが常に揃って渡され、揃っていない組み合わせが接触点集合の生成にとって意味を持たないためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11」。

use blitz_collision::shape::任意姿勢の直方体;

use super::substep_predict::細分の動的剛体;
use crate::rigid_body::{剛体の識別子, 配置};

pub(super) struct 接触点集合を作る配置 {
    pub(super) 識別子: 剛体の識別子,
    pub(super) 配置: 配置,
    pub(super) 直方体: 任意姿勢の直方体,
}

/// 細分1本の予測が終わった時点の、解く対象の剛体と、接触点集合の生成へ渡す配置の一覧。
pub(super) struct 細分の予測の結果 {
    pub(super) 動的剛体一覧: Vec<細分の動的剛体>,
    pub(super) 接触点集合を作る配置一覧: Vec<接触点集合を作る配置>,
}

impl 細分の予測の結果 {
    pub(super) fn 空から始める() -> Self {
        Self {
            動的剛体一覧: Vec::new(),
            接触点集合を作る配置一覧: Vec::new(),
        }
    }

    pub(super) fn 動かない剛体を足す(&mut self, 識別子: 剛体の識別子, 配置: 配置, 直方体: 任意姿勢の直方体) {
        self.接触点集合を作る配置一覧.push(接触点集合を作る配置 {
            識別子, 配置, 直方体
        });
    }

    pub(super) fn 予測した剛体を足す(&mut self, 予測した剛体: 細分の動的剛体, 直方体: 任意姿勢の直方体) {
        self.接触点集合を作る配置一覧.push(接触点集合を作る配置 {
            識別子: 予測した剛体.識別子,
            配置: *予測した剛体.予測.配置(),
            直方体,
        });
        self.動的剛体一覧.push(予測した剛体);
    }
}
