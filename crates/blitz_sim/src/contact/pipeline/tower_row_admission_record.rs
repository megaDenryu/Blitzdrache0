//! 箱10段の塔を、いまの本番・設計候補(i)・設計候補(i')の3つの許容差の適用規則で600刻み走らせて対にする計器
//! (Issue #59の第4段階の段階A3。判断18)。合否は判定しない。
//! 坂の場面は剛体と静的世界の接触だけであり、候補(i)(i')は剛体どうしの接触の経路にも同時に効く。この計器は、
//! 坂以外で壊れないかを見るために、休止に至った刻み・錨を置き直した拘束の延べ数・粘着の候補が解けなかった延べ数・
//! 生成時の食い込みの最大・有効集合の探索が解いた連立方程式の回数を、3つの適用規則で並べる。
//! 数える対象と数え方は `tower_run_tally` が持ち、この工程は場面を組んで適用規則を差し替えて回す側である。
//! 場面は `tower_rest_tests` と同じ `箱の塔の場面を作る(10, false)`(細分数16・600刻み)であり、休止の判定も
//! 同じ「全部の箱の実行状態が休止しているか」を刻みの末に読む形である。
//! 実行は `cargo test -p blitz_sim --release 行を積まない候補_塔を三つの適用規則で綴る -- --ignored --nocapture` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::tower_fixture::箱の塔の場面を作る;
use super::tower_run_tally::塔の走行の数え;
use crate::contact::normal_tangential_system::{
    接線の行への許容差の適用規則, 解けたと見なす許容差の倍率, 試験の許容差の適用規則
};
use crate::rigid_body::{剛体の台帳, 剛体の識別子};

const 綴る刻みの数: usize = 600;
const 塔の段数: u16 = 10;
const 測る三つの適用規則: [接線の行への許容差の適用規則; 3] = [
    接線の行への許容差の適用規則::全部の拘束行を追加し右辺に受理の倍率を掛けた許容差を残す,
    接線の行への許容差の適用規則::全部の拘束行を追加し右辺から許容差を外す,
    接線の行への許容差の適用規則::許容差以下の接線変位の拘束行を追加しない,
];

fn 全部の箱が休止したか(台帳: &剛体の台帳, 箱id一覧: &[剛体の識別子]) -> bool {
    箱id一覧
        .iter()
        .all(|&id| 台帳.参照する(id).is_ok_and(|剛体| 剛体.実行状態().休止しているか()))
}

fn 一つの適用規則を綴る(行への適用規則: 接線の行への許容差の適用規則) {
    let (mut 工程, mut 台帳, 箱id一覧, _) = 箱の塔の場面を作る(塔の段数, false);
    工程
        .解法
        .計器
        .許容差の適用規則を差し替える(試験の許容差の適用規則::倍率と行への適用規則から生成する(
            解けたと見なす許容差の倍率::既定で生成する(),
            行への適用規則,
        ));
    let mut 数え = 塔の走行の数え::零から始める();
    for 刻み in 0..綴る刻みの数 {
        let Ok(細分ごと) = 工程.一刻み進めて細分ごとのバッチを返す(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        数え.一刻みを数える(&細分ごと, 刻み, 全部の箱が休止したか(&台帳, &箱id一覧), &工程.解法.計器);
    }
    println!("[{行への適用規則:?}] {}", 数え.綴り(&工程.解法.計器));
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 行を積まない候補_塔を三つの適用規則で綴る() {
    for 行への適用規則 in 測る三つの適用規則 {
        一つの適用規則を綴る(行への適用規則);
    }
}
