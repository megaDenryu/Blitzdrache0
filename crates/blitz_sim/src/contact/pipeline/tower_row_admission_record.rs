//! 箱10段の塔を、いまの本番・設計候補(i)・設計候補(i')の3つの許容差の当て方で600刻み走らせて対にする計器
//! (Issue #59の第4段階の段階A3。判断18)。合否は判定しない。
//! 坂の場面は剛体と静的世界の接触だけであり、候補(i)(i')は剛体どうしの接触の経路にも同時に効く。この計器は、
//! 坂以外で壊れないかを見るために、休止に至った刻み・錨を置き直した拘束の延べ数・粘着の候補が解けなかった延べ数・
//! 生成時の食い込みの最大・有効集合の探索が解いた連立の回数を、3つの当て方で並べる。
//! 1本目の塔が休止することは `tower_rest_tests` が固定しており、この計器はその刻みが当て方で動くかを読む。
//! 実行は `cargo test -p blitz_sim --release 行を積まない候補_塔を三つの当て方で綴る -- --ignored --nocapture` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::tower_fixture::箱の塔の場面を作る;
use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::normal_tangential_system::{
    接線の行への許容差の当て方, 解けたと見なす許容差の倍率, 試験の許容差の当て方
};
use crate::rigid_body::{剛体の台帳, 剛体の識別子};

const 綴る刻みの数: usize = 600;
const 塔の段数: u16 = 10;
const 測る三つの当て方: [接線の行への許容差の当て方; 3] = [
    接線の行への許容差の当て方::右辺へ受理の倍率を掛けて残す,
    接線の行への許容差の当て方::右辺を零にする,
    接線の行への許容差の当て方::許容差の内側の点の行を積まず右辺を零にする,
];

// 1つの当て方で600刻み走らせたあいだに数えた量。
struct 塔の走行の数え {
    休止に至った刻み: Option<usize>,
    錨を置き直した拘束の延べ数: usize,
    最大の食い込み: f32,
}

fn 錨を置き直した拘束の数(バッチ: &接触拘束の二つのバッチ) -> usize {
    バッチ
        .剛体どうしの接触拘束()
        .iter()
        .filter(|拘束| 拘束.静止摩擦の解の状態().錨を置き直したか())
        .count()
        + バッチ
            .剛体と静的世界の接触拘束()
            .iter()
            .filter(|拘束| 拘束.静止摩擦の解の状態().錨を置き直したか())
            .count()
}

fn 最大の食い込み(バッチ: &接触拘束の二つのバッチ) -> f32 {
    let 剛体どうし = バッチ
        .剛体どうしの接触拘束()
        .iter()
        .map(|拘束| 拘束.引数().生成時の符号付き貫通量.長さ().値());
    let 静的世界 = バッチ
        .剛体と静的世界の接触拘束()
        .iter()
        .map(|拘束| 拘束.引数().生成時の符号付き貫通量.長さ().値());
    剛体どうし.chain(静的世界).fold(0.0, f32::max)
}

fn 全部の箱が休止したか(台帳: &剛体の台帳, 箱id一覧: &[剛体の識別子]) -> bool {
    箱id一覧
        .iter()
        .all(|&id| 台帳.参照する(id).is_ok_and(|剛体| 剛体.実行状態().休止しているか()))
}

fn 一つの当て方を綴る(行への当て方: 接線の行への許容差の当て方) {
    let (mut 工程, mut 台帳, 箱id一覧, _) = 箱の塔の場面を作る(塔の段数, false);
    工程
        .解法
        .計器
        .許容差の当て方を差し替える(試験の許容差の当て方::倍率と行への当て方から生成する(
            解けたと見なす許容差の倍率::既定で生成する(),
            行への当て方,
        ));
    let mut 数え = 塔の走行の数え {
        休止に至った刻み: None,
        錨を置き直した拘束の延べ数: 0,
        最大の食い込み: 0.0,
    };
    for 刻み in 0..綴る刻みの数 {
        let Ok(細分ごと) = 工程.一刻み進めて細分ごとのバッチを返す(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        for バッチ in &細分ごと {
            数え.錨を置き直した拘束の延べ数 += 錨を置き直した拘束の数(バッチ);
            数え.最大の食い込み = 数え.最大の食い込み.max(最大の食い込み(バッチ));
        }
        if 数え.休止に至った刻み.is_none() && 全部の箱が休止したか(&台帳, &箱id一覧) {
            数え.休止に至った刻み = Some(刻み);
        }
    }
    let 解いた回数 = 工程.解法.計器.解いた回数の累計を読んで零に戻す();
    println!(
        "[{行への当て方:?}] 休止に至った刻み={:?} 錨の置き直しの延べ数={} 解けず{}(うち精度不足{}) 最大の食い込み={:.4e} 解いた回数={}",
        数え.休止に至った刻み,
        数え.錨を置き直した拘束の延べ数,
        工程.解法.計器.粘着の候補が解けなかった延べ数(),
        工程.解法.計器.表現の精度が不足した延べ数(),
        数え.最大の食い込み,
        解いた回数.階層の走査が解いた数()
    );
}

