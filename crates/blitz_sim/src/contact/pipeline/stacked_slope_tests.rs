//! 坂の上に2段に積んだ動的な箱で、受理の許容差の倍率を振っても保持と滑走が変わらないことの試験(判断13の2026-09-12の
//! 実装の細目の反証(4)(e)。Issue #59の第4段階)。両側の錨が動的剛体の局所量である単純な面接触(上の箱と下の箱)を、
//! 塔以外の動的剛体どうしの検査として置く。場面は `stacked_slope_fixture` が組む。
//! 固定するのは1つである。静止摩擦係数0.6・正接0.55の坂で、受理の倍率0.5倍・1倍・2倍の分類が同じであること。
//! 保持であることは要求しない。3つの倍率とも滑走であり、旧の形(右辺に δ を残す形)も同じ場面で滑走する。原因は未確定で
//! あり、一次計測(記録の表31)で円錐を超える対と細分を確定してから保持の要求を置く。
//! 箱を立方体でなく坂の下り向きに長い平たい直方体(半分の長さ [0.5, 0.25, 1.0] メートル)にするのは、立方体を2つ積むと
//! 転倒の限界の正接が 箱の下り向きの半分の長さ ÷ 2段の全系の重心の高さ = 0.5 ÷ 1.0 = 0.5 となり、この試験が見る正接0.55に
//! 静止の解が存在しないためである。平たい箱では同じ式が 1.0 ÷ 0.5 = 2.0 になり、正接0.55はその内側に入る。転倒を
//! 滑走の原因から除外した計測として、この作り直しは残す(下の箱の坂の面に対する傾きの正接の最大は0.036である)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::stacked_slope_fixture::坂の上の二段の箱の場面;
use super::stacked_slope_spec::原点;
use crate::contact::friction_coefficient::摩擦係数;
use crate::contact::normal_tangential_system::{解けたと見なす許容差の倍率, 試験の許容差の適用規則};
use crate::rigid_body::剛体の識別子;

const 保持を見る刻み数: usize = 600;
const 傾きの正接: f32 = 0.55;
const 静止摩擦係数の値: f32 = 0.6;
const 保持を要求する変位の上限: f32 = 1.0e-3;
const 振る受理の倍率: &[f32] = &[0.5, 1.0, 2.0];

/// 2段の箱の保持と滑走の分類。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum 二段の箱の保持と滑走 {
    保持,
    滑走,
}

fn 重心の下り向きの成分(場面: &坂の上の二段の箱の場面, 箱: 剛体の識別子) -> f32 {
    let Ok(剛体) = 場面.台帳.参照する(箱) else {
        panic!("箱が台帳に無い");
    };
    (剛体.配置().重心の位置() - 原点()).方向に沿う長さ(場面.幾何.下り向き()).値()
}

// 受理の倍率を差し替えて600刻み進め、2つの箱の坂に沿った変位と最後の刻みの滑走中の接触点から分類する。
fn 受理の倍率で分類する(受理の倍率: f32) -> 二段の箱の保持と滑走 {
    let Ok(摩擦) = 摩擦係数::生成する(静止摩擦係数の値) else {
        panic!("摩擦係数を作れない");
    };
    let mut 場面 = 坂の上の二段の箱の場面::生成する(傾きの正接, 摩擦);
    場面.工程.解法.計器.許容差の適用規則を差し替える(
        試験の許容差の適用規則::本番と同じ適用規則()
            .受理の倍率を差し替える(解けたと見なす許容差の倍率::比から生成する(受理の倍率)),
    );
    let 初めの下 = 重心の下り向きの成分(&場面, 場面.下の箱);
    let 初めの上 = 重心の下り向きの成分(&場面, 場面.上の箱);
    let mut 最後の刻みに滑走中の点があった = false;
    for 刻み in 0..保持を見る刻み数 {
        let Ok(細分ごと) = 場面.工程.一刻み進めて細分ごとのバッチを返す(&mut 場面.台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        最後の刻みに滑走中の点があった = 細分ごと
            .last()
            .is_some_and(|バッチ| バッチ.剛体どうしの接触拘束().iter().any(|拘束| 拘束.静止摩擦の解の状態().滑走中か()));
    }
    let 下の変位 = 重心の下り向きの成分(&場面, 場面.下の箱) - 初めの下;
    let 上の変位 = 重心の下り向きの成分(&場面, 場面.上の箱) - 初めの上;
    let 変位の内側 = 下の変位.abs() <= 保持を要求する変位の上限 && 上の変位.abs() <= 保持を要求する変位の上限;
    if 変位の内側 && !最後の刻みに滑走中の点があった {
        二段の箱の保持と滑走::保持
    } else {
        二段の箱の保持と滑走::滑走
    }
}

#[test]
fn 坂の上の二段の箱は受理の倍率を振っても分類が変わらない() {
    let 一倍の分類 = 受理の倍率で分類する(1.0);
    for &受理の倍率 in 振る受理の倍率 {
        assert_eq!(
            受理の倍率で分類する(受理の倍率),
            一倍の分類,
            "受理{受理の倍率}倍で坂の上の2段の箱の正接{傾きの正接}の分類が1倍と違う"
        );
    }
}
