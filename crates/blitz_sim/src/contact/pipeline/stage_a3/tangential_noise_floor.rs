//! Issue #103の段階A3の計測Bのうち、剛体どうしの接触(箱10段の塔と坂の上の2段の箱)の側の計器。刻みごとに、
//! 受理の判定を通った連立方程式が持つ錨からの接線変位の長さ |C_t| の最大を綴る。保持している物体の |C_t| は
//! 物理の滑りでなく表現の刻みと演算の丸めが作る雑音であり、この床が候補(θ)が据える1つの長さの根拠になる。
//! 坂の側は
//! `crates/blitz_sim/src/contact/scene/numeric_contract_record/tolerance_dependence/eigen_direction_switch/tangential_noise_floor.rs` が別に綴る。
//! 剛体どうしの接触を別に測るのは、両側の錨が動く剛体の局所量であり、片側が静的世界である坂と雑音の由来が違うためである。
//! 合否は判定しない。実行は `cargo test -p blitz_sim --release 接線の雑音の床_剛体どうし -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::stacked_slope_fixture::坂の上の二段の箱の場面;
use super::super::tower_fixture::箱の塔の場面を作る;
use crate::contact::friction_coefficient::摩擦係数;

const 塔の段数: u16 = 10;
const 二段の箱の傾きの正接: f32 = 0.55;
const 綴る刻みの数: usize = 60;
const 刻みを綴る間隔: usize = 5;

// 刻みごとの |C_t| の最大を綴り、全体の最大を返す。
fn 一刻みの床を綴る(見出し: &str, 刻み: usize, 最大: f32, 全体の最大: f32) -> f32 {
    if 刻み % 刻みを綴る間隔 == 0 {
        println!("  M [{見出し}] 刻み{刻み} |C_t|の最大={最大:.4e}");
    }
    全体の最大.max(最大)
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 接線の雑音の床_剛体どうしの二場面を綴る() {
    塔の床を綴る();
    二段の箱の床を綴る();
}

fn 塔の床を綴る() {
    let 見出し = format!("箱{塔の段数}段の塔_本番の適用規則");
    let (mut 工程, mut 台帳, _, _) = 箱の塔の場面を作る(塔の段数, false);
    let mut 全体の最大 = 0.0f32;
    for 刻み in 0..綴る刻みの数 {
        let Ok(_) = 工程.一刻み進めて細分ごとのバッチを返す(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        全体の最大 = 一刻みの床を綴る(&見出し, 刻み, 工程.解法.計器.接線変位の長さの最大を読んで零に戻す(), 全体の最大);
    }
    println!("  要約 [{見出し}] {綴る刻みの数}刻みの |C_t| の最大={全体の最大:.4e}");
}

fn 二段の箱の床を綴る() {
    let 見出し = format!("坂の上の二段の箱_正接{二段の箱の傾きの正接}_本番の適用規則");
    let Ok(摩擦) = 摩擦係数::生成する(0.6) else {
        panic!("摩擦係数を作れない");
    };
    let mut 場面 = 坂の上の二段の箱の場面::生成する(二段の箱の傾きの正接, 摩擦);
    let mut 全体の最大 = 0.0f32;
    for 刻み in 0..綴る刻みの数 {
        let Ok(_) = 場面.工程.一刻み進めて細分ごとのバッチを返す(&mut 場面.台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        全体の最大 = 一刻みの床を綴る(&見出し, 刻み, 場面.工程.解法.計器.接線変位の長さの最大を読んで零に戻す(), 全体の最大);
    }
    println!("  要約 [{見出し}] {綴る刻みの数}刻みの |C_t| の最大={全体の最大:.4e}");
}
