//! Issue #103の段階A5の計測15。箱10段の塔を**本番の適用規則で**進め、その1つの軌道の上で、3つの判定が
//! 捨てたであろう向きを同じ固有分解の上で数える計器(親の2026-09-12の指示)。枝の判定は解へ1ビットも反映しない。
//! これが要るのは、段階A5の表74が枝ごとに別々の軌道を走らせており、そこから「どの枝が本番より多く捨てたか」を
//! 読めないためである(連言の枝は定義上、本番が捨てる向きの部分集合しか捨てないのに、別々の軌道では本番の5本より
//! 多い16本から51本を捨てたと出た)。同じ軌道の上で数えれば、その食い違いは消える。
//! 数えるのは、本番が捨てて連言が解くことになる向きの本数と、その向きの正規化した増分の桁ごとの度数である。
//! これが分かれば、塔が休止しなくなる原因が「正当性の無い捨てを1本ずつやめたこと」なのかを、軌道を走らせずに読める。
//! 向きごとの5つの量は、刻み0の求解だけ1行ずつ綴る。120刻みの全部の求解を綴ると行が百万を超えるためである。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 同じ軌道の上で判定を比べる -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::tower_fixture::箱の塔の場面を作る;
use super::counterfactual_tally::判定ごとの捨てた本数の数え;
use crate::contact::normal_tangential_system::単精度の解の内訳;

const 塔の段数: u16 = 10;
const 綴る刻みの数: usize = 120;
// 向きごとの5つの量を1行ずつ綴る刻み。これより後の刻みは数えるだけである。
const 向きごとを綴る刻み: usize = 0;

fn 一回の求解の向きを綴る(
    刻み: usize, 求解: usize, 内訳: &単精度の解の内訳, 数え: &判定ごとの捨てた本数の数え
) {
    for (k, 向き) in 内訳.固有の向きごと.iter().enumerate() {
        println!("    P 刻み{刻み} 求解{求解} 向き{k} {}", 数え.一つの向きの綴り(内訳, 向き));
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 同じ軌道の上で判定を比べる_箱十段の塔を本番の軌道で綴る() {
    let (mut 工程, mut 台帳, _, _) = 箱の塔の場面を作る(塔の段数, false);
    工程.解法.計器.定まった解の内訳を数え始めて溜まった分を読む();
    let mut 数え = 判定ごとの捨てた本数の数え::出発点から始める();
    for 刻み in 0..綴る刻みの数 {
        let Ok(_) = 工程.一刻み進めて細分ごとのバッチを返す(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        for (求解, 内訳) in 工程.解法.計器.定まった解の内訳を数え始めて溜まった分を読む().iter().enumerate() {
            数え.一回の求解を数える(内訳);
            if 刻み == 向きごとを綴る刻み {
                一回の求解の向きを綴る(刻み, 求解, 内訳, &数え);
            }
        }
    }
    println!("  要約 [箱{塔の段数}段の塔_本番の軌道_{綴る刻みの数}刻み] {}", 数え.綴り());
}
