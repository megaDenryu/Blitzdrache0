//! Issue #103の段階A5の計測16が読む、1刻みの休止の質(試験と計器の専用)。
//! 箱ごとの速さ・角速度の大きさ・静穏が続いた細分の本数・休止しているかを台帳から読み、刻みの要約へ畳む。
//! 走らせる工程(`tower_rest_quality`)から分けているのは、あちらが塔を進める局面であり、こちらが進め終えた台帳を
//! 読むだけの局面だからである。この工程はどの状態も書き換えない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 動的剛体は接触島ごとに静穏が続いた時間で休止し、新しい接触で起きる」

#![cfg(test)]

use crate::rigid_body::{剛体の台帳, 剛体の識別子, 運動種別};

/// 箱1つの読み取り。
struct 箱一つの読み取り {
    速さ: f32,
    角速度の大きさ: f32,
    静穏が続いた細分の本数: u32,
    休止しているか: bool,
}

/// 1刻みの終わりに台帳から読んだ、塔の休止の質。
pub(super) struct 一刻みの休止の質の読み取り {
    箱ごと: Vec<箱一つの読み取り>,
    元の行空間の残差の最大: f32,
}

impl 一刻みの休止の質の読み取り {
    pub(super) fn 台帳から読む(
        台帳: &剛体の台帳, 箱の識別子一覧: &[剛体の識別子], 元の行空間の残差の最大: f32
    ) -> Self {
        let 箱ごと = 箱の識別子一覧
            .iter()
            .map(|&id| {
                let Ok(剛体) = 台帳.参照する(id) else {
                    return 箱一つの読み取り {
                        速さ: 0.0,
                        角速度の大きさ: 0.0,
                        静穏が続いた細分の本数: 0,
                        休止しているか: false,
                    };
                };
                let 速度 = 剛体.運動種別().速度();
                箱一つの読み取り {
                    速さ: 速度.map_or(0.0, |状態| 状態.並進速度().長さ().値()),
                    角速度の大きさ: 速度.map_or(0.0, |状態| 状態.角速度().長さ().値()),
                    静穏が続いた細分の本数: match 剛体.運動種別() {
                        運動種別::動的 {
                            静穏が続いた細分の本数,
                        ..
                        } => 静穏が続いた細分の本数.本数(),
                        運動種別::静的 | 運動種別::運動学的 { .. } => 0,
                    },
                    休止しているか: 剛体.実行状態().休止しているか(),
                }
            })
            .collect();
        Self {
            箱ごと,
            元の行空間の残差の最大,
        }
    }

    /// 刻み1本の要約。
    pub(super) fn 要約の綴り(&self) -> String {
        let 速さの最大 = self.箱ごと.iter().map(|箱| 箱.速さ).fold(0.0, f32::max);
        let 角速度の最大 = self.箱ごと.iter().map(|箱| 箱.角速度の大きさ).fold(0.0, f32::max);
        let 休止した数 = self.箱ごと.iter().filter(|箱| 箱.休止しているか).count();
        let 静穏の本数の最小 = self.箱ごと.iter().map(|箱| 箱.静穏が続いた細分の本数).min().unwrap_or(0);
        format!(
            "速さの最大={速さの最大:.4e} 角速度の大きさの最大={角速度の最大:.4e} 休止した箱={休止した数}個 静穏が続いた細分の本数の最小={静穏の本数の最小} 元の行空間の残差の最大={:.4e}",
            self.元の行空間の残差の最大
        )
    }

    /// 箱1つずつの行。
    pub(super) fn 箱ごとの綴り(&self) -> Vec<String> {
        self.箱ごと
            .iter()
            .enumerate()
            .map(|(番号, 箱)| {
                format!(
                    "箱{番号} 速さ={:.4e} 角速度の大きさ={:.4e} 静穏が続いた細分の本数={} 休止={}",
                    箱.速さ, 箱.角速度の大きさ, 箱.静穏が続いた細分の本数, 箱.休止しているか
                )
            })
            .collect()
    }
}
