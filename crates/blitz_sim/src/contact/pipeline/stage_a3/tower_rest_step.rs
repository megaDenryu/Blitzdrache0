//! Issue #103の段階A3の計測E。箱10段の塔が全部の箱を休止させるまでの刻みを、本番の形と候補(θ)の適用規則で対にして
//! 綴る計器(親の2026-09-12の指示)。候補(θ)は擬似逆の右辺の判定が比べる δ_i だけを接線の雑音の床へ安全率を掛けた
//! 1つの長さへ差し替える枝であり、坂の保持を守った代わりに剛体どうしの接触で退行していないかをこの刻みで読む。
//! 段階A4の候補(θ')も同じ刻みで読む。候補(θ')は同じ δ_i を1つの長さでなく、衝突の問い合わせの基準原点に相対な
//! 座標の刻みから行ごとに導く枝であり、剛体どうしの接触では行ごとに腕の大きさで決まる値になる。
//! 刻みごとの詳しい内訳(接触点の数の分布・面の隔たり)は`tower_rest_probe`が別に綴る。こちらは休止までの刻みと、
//! 錨の置き直しと滑走中の拘束と粘着の候補が解けなかった延べ数だけを1行へ畳む。合否は判定しない。
//! 実行は `cargo test -p blitz_sim --release 塔の休止の刻み -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::body_scene_run::剛体どうしの場面の走行;
use crate::contact::normal_tangential_system::{擬似逆が右辺の向きを捨てる判定の当て方, 試験の許容差の当て方};

const 塔の段数: u16 = 10;
const 綴る刻みの数: usize = 120;
// 段階A2の追補の表42が測った接線変位の雑音の床と、候補(θ)がそれへ掛ける安全率。
const 接線の雑音の床メートル: f32 = 6.65e-8;
const 雑音の床へ掛ける安全率: f32 = 4.0;

fn 一つの適用規則の休止の刻みを綴る(見出し: &str, 適用規則: 試験の許容差の当て方) {
    let mut 走行 = 剛体どうしの場面の走行::箱の塔から始める(塔の段数, 適用規則);
    let (mut 全部が休止した刻み, mut 置き直しの延べ数, mut 滑走中の延べ数) = (None, 0, 0);
    for _ in 0..綴る刻みの数 {
        let 刻み = 走行.終えた刻みの数();
        let 細分ごと = 走行.一刻み進める();
        for バッチ in &細分ごと {
            for 拘束 in バッチ.剛体どうしの接触拘束() {
                置き直しの延べ数 += usize::from(拘束.静止摩擦の解の状態().錨を置き直したか());
                滑走中の延べ数 += usize::from(拘束.静止摩擦の解の状態().滑走中か());
            }
        }
        if 走行.全部の箱が休止しているか() && 全部が休止した刻み.is_none() {
            全部が休止した刻み = Some(刻み);
        }
    }
    let (解けなかった延べ数, 精度が不足した延べ数) = 走行.解けなかった延べ数と精度不足の延べ数();
    println!(
        "  N [箱{塔の段数}段の塔_{見出し}] 全部が休止した刻み={全部が休止した刻み:?} 置き直し={置き直しの延べ数} 滑走中={滑走中の延べ数} 解けず{解けなかった延べ数}(精度不足{精度が不足した延べ数})"
    );
}

