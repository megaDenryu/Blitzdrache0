//! Issue #103の段階A5の計測15が使う、判定ごとの捨てた本数の数え(試験と計器の専用)。
//! 1つの固有分解の上で、3つの判定が第k番の向きを捨てるかどうかを、解へ反映せずに読む。
//! 判定はどれも解の内訳が持つ量だけから決まるため、この数えは固有分解を組み直さない。
//! 本番は右辺の射影が向きへ積み上げた許容差の内側かで捨て、相対固有値の枝は最大の固有値への相対比が閾値以下かで
//! 捨て、連言の枝は本番が捨てる向きのうち捨てる正当性が在るものだけを捨てる。
//! 走らせる工程(`counterfactual_discard`)から分けているのは、あちらが塔を進める局面であり、こちらが読んだ内訳を
//! 数へ畳む工程だからである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use crate::contact::normal_tangential_system::{単精度の固有の向きの内訳, 単精度の解の内訳, 桁ごとの度数};

// 段階A5が出発点として選んだ2つの値。
const 相対比の出発点: f32 = 2.1e-5;
const 増分の倍率の出発点: f32 = 100.0;

/// 同じ軌道の上で3つの判定が捨てた本数と、本番が捨てて連言が解く向きの増分の広がり。
pub(super) struct 判定ごとの捨てた本数の数え {
    数えた求解の数: usize,
    数えた向きの本数: usize,
    偽の固有値で捨てた本数: usize,
    本番が捨てた本数: usize,
    相対固有値の枝が捨てた本数: usize,
    連言の枝が捨てた本数: usize,
    本番が捨てて連言が解く本数: usize,
    本番が捨てて連言が解く向きの増分の度数: 桁ごとの度数,
    本番が捨てて連言が解く向きの増分の最大: f32,
}

impl 判定ごとの捨てた本数の数え {
    pub(super) fn 出発点から始める() -> Self {
        Self {
            数えた求解の数: 0,
            数えた向きの本数: 0,
            偽の固有値で捨てた本数: 0,
            本番が捨てた本数: 0,
            相対固有値の枝が捨てた本数: 0,
            連言の枝が捨てた本数: 0,
            本番が捨てて連言が解く本数: 0,
            本番が捨てて連言が解く向きの増分の度数: 桁ごとの度数::範囲から始める(-8, 12),
            本番が捨てて連言が解く向きの増分の最大: 0.0,
        }
    }

    pub(super) fn 一回の求解を数える(&mut self, 内訳: &単精度の解の内訳) {
        self.数えた求解の数 += 1;
        for 向き in &内訳.固有の向きごと {
            self.数えた向きの本数 += 1;
            if 向き.固有値 <= 内訳.偽の固有値の下限 {
                self.偽の固有値で捨てた本数 += 1;
                continue;
            }
            let (本番, 相対固有値, 連言) = 三つの判定(内訳, 向き);
            self.本番が捨てた本数 += usize::from(本番);
            self.相対固有値の枝が捨てた本数 += usize::from(相対固有値);
            self.連言の枝が捨てた本数 += usize::from(連言);
            if 本番 && !連言 {
                let 増分 = 正規化した増分(内訳, 向き);
                self.本番が捨てて連言が解く本数 += 1;
                self.本番が捨てて連言が解く向きの増分の度数.一つ数える(増分);
                self.本番が捨てて連言が解く向きの増分の最大 = self.本番が捨てて連言が解く向きの増分の最大.max(増分);
            }
        }
    }

    /// 向き1本の5つの量と、3つの判定の答え。
    pub(super) fn 一つの向きの綴り(&self, 内訳: &単精度の解の内訳, 向き: &単精度の固有の向きの内訳) -> String {
        if 向き.固有値 <= 内訳.偽の固有値の下限 {
            return format!("λ/λ_max={:.4e} 偽の固有値として3つの判定とも捨てる", 相対固有値(内訳, 向き));
        }
        let (本番, 相対固有値の枝, 連言) = 三つの判定(内訳, 向き);
        format!(
            "λ/λ_max={:.4e} |β|={:.4e} δ_k={:.4e} 正規化した増分={:.4e} 本番は捨てる={本番} 相対固有値の枝は捨てる={相対固有値の枝} 連言は捨てる={連言}",
            相対固有値(内訳, 向き),
            向き.右辺の射影.abs(),
            向き.許容差の射影,
            正規化した増分(内訳, 向き)
        )
    }

    pub(super) fn 綴り(&self) -> String {
        format!(
            "求解={}件 向き={}本 偽の固有値で捨てた={}本 本番が捨てた={}本 相対固有値の枝が捨てた={}本 連言が捨てた={}本 本番が捨てて連言が解く={}本(増分の最大={:.4e}) その増分の度数[{}]",
            self.数えた求解の数,
            self.数えた向きの本数,
            self.偽の固有値で捨てた本数,
            self.本番が捨てた本数,
            self.相対固有値の枝が捨てた本数,
            self.連言の枝が捨てた本数,
            self.本番が捨てて連言が解く本数,
            self.本番が捨てて連言が解く向きの増分の最大,
            self.本番が捨てて連言が解く向きの増分の度数.綴り()
        )
    }
}

// 本番・相対固有値の枝・連言の枝の3つが、この向きを捨てるか。偽の固有値の向きはこの口へ来ない。
fn 三つの判定(内訳: &単精度の解の内訳, 向き: &単精度の固有の向きの内訳) -> (bool, bool, bool) {
    let 本番 = 向き.右辺の射影.abs() <= 向き.許容差の射影;
    let 相対固有値の枝 = 相対固有値(内訳, 向き) <= 相対比の出発点;
    let 正当性 = 相対固有値の枝 || 正規化した増分(内訳, 向き) >= 増分の倍率の出発点;
    (本番, 相対固有値の枝, 本番 && 正当性)
}

fn 相対固有値(内訳: &単精度の解の内訳, 向き: &単精度の固有の向きの内訳) -> f32 {
    if 内訳.最大の固有値 > 0.0 {
        向き.固有値 / 内訳.最大の固有値
    } else {
        0.0
    }
}

fn 正規化した増分(内訳: &単精度の解の内訳, 向き: &単精度の固有の向きの内訳) -> f32 {
    let 分母 = 内訳.右辺をいちばん硬い向きで解いたときの増分();
    if 分母 > 0.0 && 向き.固有値 > 0.0 {
        (向き.右辺の射影 / 向き.固有値).abs() / 分母
    } else {
        0.0
    }
}
