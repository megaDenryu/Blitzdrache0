//! Issue #103の段階A5の計測15が使う、判定ごとの捨てた本数の数え(試験と計器の専用)。
//! 1つの軌道の上で、3つの判定が捨てた本数を溜め、本番が捨てて連言が解く向きについては、正規化した増分と
//! 相対固有値の2つを桁ごとに数える。相対固有値の度数が要るのは、その群が弱い向きへ偏っているかを読むためである。
//! 偏っているなら、向きの強さで2つの群を分けられる可能性が残る。偏っていないなら、強さでは分けられない。
//! 向き1本の判定と量は`counterfactual_direction`が読み、走らせる工程は`counterfactual_discard`が持つ。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::counterfactual_direction::{三つの判定の答え, 正規化した増分, 相対固有値};
use crate::contact::normal_tangential_system::{単精度の固有の向きの内訳, 単精度の解の内訳, 桁ごとの度数};

/// 同じ軌道の上で3つの判定が捨てた本数と、本番が捨てて連言が解く向きの2つの広がり。
pub(super) struct 判定ごとの捨てた本数の数え {
    数えた求解の数: usize,
    数えた向きの本数: usize,
    偽の固有値で捨てた本数: usize,
    本番が捨てた本数: usize,
    相対固有値の枝が捨てた本数: usize,
    連言の枝が捨てた本数: usize,
    本番が捨てて連言が解く本数: usize,
    本番が捨てて連言が解く向きの増分の度数: 桁ごとの度数,
    本番が捨てて連言が解く向きの相対固有値の度数: 桁ごとの度数,
    本番が捨てて連言が解く向きの増分の最大: f32,
}

impl 判定ごとの捨てた本数の数え {
    pub(super) fn 出発点から始める() -> Self {
        Self {
            数えた求解の数: 0,
            数えた向きの本数: 0,
            偽の固有値で捨てた本数: 0,
            本番が捨てた本数: 0,
            相対固有値の枝が捨てた本数: 0,
            連言の枝が捨てた本数: 0,
            本番が捨てて連言が解く本数: 0,
            本番が捨てて連言が解く向きの増分の度数: 桁ごとの度数::範囲から始める(-8, 12),
            本番が捨てて連言が解く向きの相対固有値の度数: 桁ごとの度数::範囲から始める(-8, 10),
            本番が捨てて連言が解く向きの増分の最大: 0.0,
        }
    }

    pub(super) fn 一回の求解を数える(&mut self, 内訳: &単精度の解の内訳) {
        self.数えた求解の数 += 1;
        for 向き in &内訳.固有の向きごと {
            self.数えた向きの本数 += 1;
            if 向き.固有値 <= 内訳.偽の固有値の下限 {
                self.偽の固有値で捨てた本数 += 1;
                continue;
            }
            let 答え = 三つの判定の答え::内訳と向きから読む(内訳, 向き);
            self.本番が捨てた本数 += usize::from(答え.本番が捨てる);
            self.相対固有値の枝が捨てた本数 += usize::from(答え.相対固有値の枝が捨てる);
            self.連言の枝が捨てた本数 += usize::from(答え.連言の枝が捨てる);
            if 答え.本番が捨てる && !答え.連言の枝が捨てる {
                self.本番だけが捨てる向きを数える(内訳, 向き);
            }
        }
    }

    fn 本番だけが捨てる向きを数える(&mut self, 内訳: &単精度の解の内訳, 向き: &単精度の固有の向きの内訳) {
        let 増分 = 正規化した増分(内訳, 向き);
        self.本番が捨てて連言が解く本数 += 1;
        self.本番が捨てて連言が解く向きの増分の度数.一つ数える(増分);
        self.本番が捨てて連言が解く向きの相対固有値の度数.一つ数える(相対固有値(内訳, 向き));
        self.本番が捨てて連言が解く向きの増分の最大 = self.本番が捨てて連言が解く向きの増分の最大.max(増分);
    }

    /// 向き1本の量と、3つの判定の答え。
    pub(super) fn 一つの向きの綴り(&self, 内訳: &単精度の解の内訳, 向き: &単精度の固有の向きの内訳) -> String {
        if 向き.固有値 <= 内訳.偽の固有値の下限 {
            return format!("λ/λ_max={:.4e} 偽の固有値として3つの判定とも捨てる", 相対固有値(内訳, 向き));
        }
        let 答え = 三つの判定の答え::内訳と向きから読む(内訳, 向き);
        format!(
            "λ/λ_max={:.4e} |β|={:.4e} δ_k={:.4e} 正規化した増分={:.4e} 本番は捨てる={} 相対固有値の枝は捨てる={} 連言は捨てる={}",
            相対固有値(内訳, 向き),
            向き.右辺の射影.abs(),
            向き.許容差の射影,
            正規化した増分(内訳, 向き),
            答え.本番が捨てる,
            答え.相対固有値の枝が捨てる,
            答え.連言の枝が捨てる
        )
    }

    pub(super) fn 綴り(&self) -> String {
        format!(
            "求解={}件 向き={}本 偽の固有値で捨てた={}本 本番が捨てた={}本 相対固有値の枝が捨てた={}本 連言が捨てた={}本 本番が捨てて連言が解く={}本(増分の最大={:.4e}) その増分の度数[{}] その相対固有値の度数[{}]",
            self.数えた求解の数,
            self.数えた向きの本数,
            self.偽の固有値で捨てた本数,
            self.本番が捨てた本数,
            self.相対固有値の枝が捨てた本数,
            self.連言の枝が捨てた本数,
            self.本番が捨てて連言が解く本数,
            self.本番が捨てて連言が解く向きの増分の最大,
            self.本番が捨てて連言が解く向きの増分の度数.綴り(),
            self.本番が捨てて連言が解く向きの相対固有値の度数.綴り()
        )
    }
}
