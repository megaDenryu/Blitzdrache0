//! Issue #103の段階A5の計測7。箱10段の塔の1刻み(細分16本)のあいだに定まった全部の求解について、擬似逆が
//! 捨てた向きの本数と解いた向きの本数を、本番の適用規則と候補(θ)で対にして数える計器(親の2026-09-12の指示)。
//! これが要るのは、候補(θ)が塔を休止させなくなった機構について、記録の中に逆向きの2つの読みが残っているためである。
//! 段階A3の結論3は「据えた1つの長さ 2.66e-7 は剛体どうしの接触の |C_t| に対して小さすぎ、擬似逆が捨てていた向きまで
//! 解くことになる」と読み、副官の予測は「2.66e-7 は接線の δ を4.5倍に上げて右辺を捨てすぎたものである」と読む。
//! 捨てすぎなのか解きすぎなのかは、捨てた向きと解いた向きの本数を数えれば決まる。
//! 捨てた理由は3つに分けて数える。偽の固有値・右辺が許容差の内側・捨てていない、である。倍率で動くのは2つ目だけである。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 塔の捨てた向きの本数 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::tower_fixture::箱の塔の場面を作る;
use crate::contact::normal_tangential_system::{擬似逆が右辺の向きを捨てる判定の当て方, 試験の許容差の当て方};
use crate::contact::symmetric_system::擬似逆が固有の向きを捨てた理由;

const 塔の段数: u16 = 10;
const 綴る刻みの数: usize = 1;
// 段階A3が候補(θ)へ据えた1つの長さ。段階A2の追補の表42が測った床 6.65e-8 メートルの4倍である。
const 候補シータの据える長さメートル: f32 = 6.65e-8 * 4.0;

fn 一つの適用規則の捨てた本数を綴る(見出し: &str, 適用規則: 試験の許容差の当て方) {
    let (mut 工程, mut 台帳, _, _) = 箱の塔の場面を作る(塔の段数, false);
    工程.解法.計器.許容差の当て方を差し替える(適用規則);
    工程.解法.計器.定まった解の内訳を数え始めて溜まった分を読む();
    let (mut 求解, mut 向き, mut 偽の固有値, mut 右辺が内側, mut 解いた) = (0, 0, 0, 0, 0);
    for 刻み in 0..綴る刻みの数 {
        let Ok(_) = 工程.一刻み進めて細分ごとのバッチを返す(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        for 内訳 in 工程.解法.計器.定まった解の内訳を数え始めて溜まった分を読む() {
            求解 += 1;
            向き += 内訳.固有の向きごと.len();
            偽の固有値 += 内訳.捨てた向きの数(擬似逆が固有の向きを捨てた理由::偽の固有値);
            右辺が内側 += 内訳.捨てた向きの数(擬似逆が固有の向きを捨てた理由::右辺が許容差の内側);
            解いた += 内訳.捨てた向きの数(擬似逆が固有の向きを捨てた理由::捨てていない);
        }
    }
    println!(
        "  U [箱{塔の段数}段の塔_{見出し}] 求解={求解}件 向き={向き}本 偽の固有値で捨てた={偽の固有値}本 右辺が許容差の内側で捨てた={右辺が内側}本 解いた={解いた}本"
    );
}

