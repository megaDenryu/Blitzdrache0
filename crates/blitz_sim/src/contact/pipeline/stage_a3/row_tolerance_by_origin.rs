//! Issue #103の段階A4の計測A。箱10段の塔を本番の適用規則で1刻み(細分16本)進め、そのあいだに定まった全部の求解の
//! 行ごとの解けたと見なす許容差 δ_i を、2つの由来で対にして綴る計器(親の2026-09-12の指示)。2つの由来とは、
//! 世界の粗い位置の刻みから導く本番の形と、衝突の問い合わせの基準原点に相対な座標の刻みから導く候補(ζ)の式である。
//! 法線の行と接線の行を分けて数えるのは、法線の行が読む向きが接触の高さの座標を、接線の行が読む向きが水平の
//! 座標だけを読むためであり、塔では法線の δ_i だけが段とともに大きくなると予測されているからである。
//! 同じ δ_i の値を持つ行をまとめるのは、その値が接触の高さの表現の刻みそのものであり、段の識別子として働くためである。
//! 箱の重心の高さも綴り、どの段の接触がどの値に当たるかを読み手が突き合わせられるようにする。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 行ごとの許容差の由来 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use std::collections::BTreeMap;

use super::body_scene_run::剛体どうしの場面の走行;
use crate::contact::normal_tangential_system::{単精度の解の内訳, 試験の許容差の当て方};

const 塔の段数: u16 = 10;
const 綴る刻みの数: usize = 1;

/// 同じ由来と同じ値の δ_i を持つ行をまとめた数え。基準原点に相対な座標から導いた側は行ごとに違うため幅で持つ。
struct 一つの許容差の値の数え {
    行の数: usize,
    基準原点由来の最小: f32,
    基準原点由来の最大: f32,
}

impl 一つの許容差の値の数え {
    fn 空から始める() -> Self {
        Self {
            行の数: 0,
            基準原点由来の最小: f32::INFINITY,
            基準原点由来の最大: 0.0,
        }
    }

    fn 一行を数える(&mut self, 基準原点由来: f32) {
        self.行の数 += 1;
        self.基準原点由来の最小 = self.基準原点由来の最小.min(基準原点由来);
        self.基準原点由来の最大 = self.基準原点由来の最大.max(基準原点由来);
    }
}

// 求解1回の全部の行を、行の種類と粗い位置から導いた δ_i の値で束ねて数える。
// 鍵の第2の欄が単精度のビット列であるのは、浮動小数点数がそのままでは並べ替えの鍵になれないためである。
fn 一つの求解を数える(内訳: &単精度の解の内訳, 数え: &mut BTreeMap<(bool, u32), 一つの許容差の値の数え>) {
    for (k, 粗い位置由来) in 内訳.行ごとの解けたと見なす許容差.iter().enumerate() {
        let 法線の行か = k < 内訳.法線の行の数;
        数え
            .entry((法線の行か, 粗い位置由来.to_bits()))
            .or_insert_with(一つの許容差の値の数え::空から始める)
            .一行を数える(内訳.行ごとの基準原点に相対な座標から導く許容差[k]);
    }
}

fn 数えた一覧を綴る(数え: &BTreeMap<(bool, u32), 一つの許容差の値の数え>) {
    for ((法線の行か, ビット列), 値ごと) in 数え {
        let 粗い位置由来 = f32::from_bits(*ビット列);
        let 行の種類 = if *法線の行か { "法線" } else { "接線" };
        println!(
            "  P [箱{塔の段数}段の塔_本番の適用規則] {行の種類} δ_i(粗い位置)={粗い位置由来:.4e} 行={} δ_i(基準原点に相対)={:.4e}〜{:.4e} 比={:.1}〜{:.1}",
            値ごと.行の数,
            値ごと.基準原点由来の最小,
            値ごと.基準原点由来の最大,
            粗い位置由来 / 値ごと.基準原点由来の最大,
            粗い位置由来 / 値ごと.基準原点由来の最小,
        );
    }
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 行ごとの許容差の由来_塔の求解を二つの由来で対にして綴る() {
    let mut 走行 = 剛体どうしの場面の走行::箱の塔から始める(塔の段数, 試験の許容差の当て方::本番と同じ当て方());
    走行.定まった解の内訳を読む();
    let mut 数え = BTreeMap::new();
    let mut 求解の数 = 0;
    for _ in 0..綴る刻みの数 {
        走行.一刻み進める();
        for 内訳 in 走行.定まった解の内訳を読む() {
            求解の数 += 1;
            一つの求解を数える(&内訳, &mut 数え);
        }
    }
    let (台帳, 箱id一覧) = 走行.台帳と箱の識別子();
    for (段, &id) in 箱id一覧.iter().enumerate() {
        let Ok(剛体) = 台帳.参照する(id) else {
            panic!("箱 {段} を台帳から読めない");
        };
        println!(
            "  P [箱{塔の段数}段の塔_本番の適用規則] 下から{}段目の箱の重心の高さ={:.6}",
            段 + 1,
            剛体.配置().重心の位置().倍精度で評価した位置().y().値()
        );
    }
    println!("  要約 [箱{塔の段数}段の塔_本番の適用規則] {綴る刻みの数}刻みで数えた求解={求解の数}件");
    数えた一覧を綴る(&数え);
}
