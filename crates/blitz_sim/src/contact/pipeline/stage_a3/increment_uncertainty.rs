const 塔の段数: u16 = 10;
const 二段の箱の傾きの正接: f32 = 0.55;
const 綴る刻みの数: usize = 1;

fn 塔の増分と率を綴る() {
    let (mut 工程, mut 台帳, _, _) = 箱の塔の場面を作る(塔の段数, false);
    工程.解法.計器.定まった解の内訳を数え始めて溜まった分を読む();
    let mut 広がり = 増分と不確かさの率の広がり::零から始める();
    for 刻み in 0..綴る刻みの数 {
        let Ok(_) = 工程.一刻み進めて細分ごとのバッチを返す(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        for 内訳 in 工程.解法.計器.定まった解の内訳を数え始めて溜まった分を読む() {
            広がり.一回の求解を数える(&内訳);
        }
    }
    println!("  要約 [箱{塔の段数}段の塔_本番の適用規則] {}", 広がり.綴り());
}

fn 二段の箱の増分と率を綴る() {
    let Ok(摩擦) = 摩擦係数::生成する(0.6) else {
        panic!("摩擦係数を作れない");
    };
    let mut 場面 = 坂の上の二段の箱の場面::生成する(二段の箱の傾きの正接, 摩擦);
    場面.工程.解法.計器.定まった解の内訳を数え始めて溜まった分を読む();
    let mut 広がり = 増分と不確かさの率の広がり::零から始める();
    for 刻み in 0..綴る刻みの数 {
        let Ok(_) = 場面.工程.一刻み進めて細分ごとのバッチを返す(&mut 場面.台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        for 内訳 in 場面.工程.解法.計器.定まった解の内訳を数え始めて溜まった分を読む() {
            広がり.一回の求解を数える(&内訳);
        }
    }
    println!("  要約 [坂の上の二段の箱_正接{二段の箱の傾きの正接}_本番の適用規則] {}", 広がり.綴り());
}

