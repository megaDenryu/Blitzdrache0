//! Issue #103の段階A5の計測5のうち、剛体どうしの接触(箱10段の塔と坂の上の2段の箱)の側の計器。1刻み(細分16本)の
//! あいだに定まった全部の求解について、向きごとの「増分 |β_k| ÷ λ_k」と「その増分が行列自身の丸めで動きうる率
//! (λ_max n ε) ÷ λ_k」の2つを桁ごとに数え、壊す向きと無害な向きを率で分ける帯が開くかを綴る。
//! 坂の側は
//! `crates/blitz_sim/src/contact/scene/numeric_contract_record/tolerance_dependence/eigen_direction_switch/increment_uncertainty_record.rs` が別に綴る。
//! 剛体どうしを別に測るのは、段階A3の表47が「固有値を最大で割った相対値では剛体どうしの接触に帯が開かない」ことを
//! 測ったためである。相対値で分けられないものが、増分と不確かさの率でなら分けられるかどうかは、測るしかない。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 増分と不確かさの率_剛体どうし -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::body_scene_run::剛体どうしの場面の走行;
use crate::contact::friction_coefficient::摩擦係数;
use crate::contact::normal_tangential_system::{増分と不確かさの率の広がり, 試験の許容差の当て方};

const 塔の段数: u16 = 10;
const 二段の箱の傾きの正接: f32 = 0.55;
const 綴る刻みの数: usize = 1;

// 1つの走行を刻みの数だけ進め、定まった全部の求解の増分と不確かさの率を数えて綴る。
fn 一つの走行の増分と率を綴る(見出し: &str, mut 走行: 剛体どうしの場面の走行) {
    走行.定まった解の内訳を読む();
    let mut 広がり = 増分と不確かさの率の広がり::零から始める();
    for _ in 0..綴る刻みの数 {
        走行.一刻み進める();
        for 内訳 in 走行.定まった解の内訳を読む() {
            広がり.一回の求解を数える(&内訳);
        }
    }
    println!("  要約 [{見出し}] {}", 広がり.綴り());
}

fn 塔の増分と率を綴る() {
    一つの走行の増分と率を綴る(
        &format!("箱{塔の段数}段の塔_本番の適用規則"),
        剛体どうしの場面の走行::箱の塔から始める(塔の段数, 試験の許容差の当て方::本番と同じ当て方()),
    );
}

fn 二段の箱の増分と率を綴る() {
    let Ok(摩擦) = 摩擦係数::生成する(0.6) else {
        panic!("摩擦係数を作れない");
    };
    一つの走行の増分と率を綴る(
        &format!("坂の上の二段の箱_正接{二段の箱の傾きの正接}_本番の適用規則"),
        剛体どうしの場面の走行::坂の上の二段の箱から始める(二段の箱の傾きの正接, 摩擦),
    );
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 増分と不確かさの率_剛体どうしの二場面を綴る() {
    塔の増分と率を綴る();
    二段の箱の増分と率を綴る();
}
