//! Issue #103の段階A5の計測16。箱10段の塔が「休止した」ことの中身を測る計器(親の2026-09-12の指示)。
//! これが要るのは、本番の休止が「解を弱めた結果として動きが小さく見えているだけ」ではないかという疑いがあるためである。
//! もしそうなら、塔の休止を合格の条件に使うこと自体が誤りであり、それは Issue #103 の裁定より重い発見になる。
//! 綴るのは刻みごとに2段である。1段目は10個の箱の速さと角速度の大きさの最大、静穏と判定された箱の数、
//! 連続して静穏であった細分の本数の最小と、その刻みの求解の元の行空間の残差の最大である。2段目は箱1つずつの
//! 速さ・角速度の大きさ・静穏が続いた細分の本数・休止しているかであり、本番が休止する刻み41の前後だけ綴る。
//! 速さが本当に小さくなっているのか、残差が大きいまま速さだけが小さいのかを、この2つの列を並べて読む。
//! 本番と連言の枝(相対比2.1e-5・倍率100)の2本を同じ形で綴る。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 塔の休止の質 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 動的剛体は接触島ごとに静穏が続いた時間で休止し、新しい接触で起きる」

#![cfg(test)]

use super::body_scene_run::剛体どうしの場面の走行;
use super::rest_quality_reading::一刻みの休止の質の読み取り;
use crate::contact::normal_tangential_system::{擬似逆が右辺の向きを捨てる判定の当て方, 試験の許容差の当て方};
use crate::contact::symmetric_system::本番の代わりに置く右辺の向きの捨て方;

const 塔の段数: u16 = 10;
const 綴る刻みの数: usize = 120;
// 本番が全部の箱を休止させる刻みの前後。この範囲だけ箱1つずつを綴る。
const 箱ごとを綴る刻みの範囲: (usize, usize) = (30, 50);
const 相対比の出発点: f32 = 2.1e-5;
const 増分の倍率の出発点: f32 = 100.0;

fn 一つの適用規則の休止の質を綴る(見出し: &str, 適用規則: 試験の許容差の当て方) {
    let mut 走行 = 剛体どうしの場面の走行::箱の塔から始める(塔の段数, 適用規則);
    走行.定まった解の内訳を読む();
    println!("[箱{塔の段数}段の塔_{見出し}] 休止の質");
    for _ in 0..綴る刻みの数 {
        let 刻み = 走行.終えた刻みの数();
        走行.一刻み進める();
        let 残差の最大 = 走行
            .定まった解の内訳を読む()
            .iter()
            .map(crate::contact::normal_tangential_system::単精度の解の内訳::行ごとの残差の最大)
            .fold(0.0, f32::max);
        let (台帳, 箱の識別子一覧) = 走行.台帳と箱の識別子();
        let 読み取り = 一刻みの休止の質の読み取り::台帳から読む(台帳, 箱の識別子一覧, 残差の最大);
        println!("  Q 刻み{刻み} {}", 読み取り.要約の綴り());
        if 刻み >= 箱ごとを綴る刻みの範囲.0 && 刻み <= 箱ごとを綴る刻みの範囲.1 {
            for 行 in 読み取り.箱ごとの綴り() {
                println!("    Q 刻み{刻み} {行}");
            }
        }
    }
}

