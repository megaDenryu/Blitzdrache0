//! 剛体どうしの接触の場面(箱の塔と坂の上の2段の箱)を1刻みずつ進める走行。段階A3から段階A6の計器が共有する。
//! この型が在るのは、9つの計器が「場面を組む・適用規則を当てる・刻みを繰り返す・進めるエラーで落ちる・全部の箱が
//! 休止したかを台帳から読む」という同じ段取りを写していたためである。坂(剛体と静的世界の接触)の側は同じ段取りを
//! `.../tolerance_dependence/eigen_direction_switch/trajectory.rs` へ切り出してある。
//! 集計の中身は各計器が持つ。この型は刻みを進めることと、進めた結果を読む口だけを持ち、何を数えるかを知らない。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::pipeline_def::剛体の接触の一刻みの工程;
use super::super::stacked_slope_fixture::坂の上の二段の箱の場面;
use super::super::tower_fixture::箱の塔の場面を作る;
use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::friction_coefficient::摩擦係数;
use crate::contact::normal_tangential_system::{単精度の解の内訳, 試験の許容差の当て方};
use crate::rigid_body::{剛体の台帳, 剛体の識別子};

/// 剛体どうしの接触の場面の走行。始める口が場面を組み、`一刻み進める`が刻みを1つ進める。
pub(super) struct 剛体どうしの場面の走行 {
    工程: 剛体の接触の一刻みの工程,
    台帳: 剛体の台帳,
    休止を見る箱の識別子: Vec<剛体の識別子>,
    終えた刻みの数: usize,
}

impl 剛体どうしの場面の走行 {
    /// 段数を指定した箱の塔を、指定の許容差の当て方で始める。床は静的である。
    pub(super) fn 箱の塔から始める(段数: u16, 適用規則: 試験の許容差の当て方) -> Self {
        let (mut 工程, 台帳, 箱の識別子一覧, _) = 箱の塔の場面を作る(段数, false);
        工程.解法.計器.許容差の当て方を差し替える(適用規則);
        Self {
            工程,
            台帳,
            休止を見る箱の識別子: 箱の識別子一覧,
            終えた刻みの数: 0,
        }
    }

    /// 坂の上の2段の箱を、本番と同じ当て方で始める。休止を見る箱は下の箱と上の箱の2つである。
    pub(super) fn 坂の上の二段の箱から始める(傾きの正接: f32, 摩擦: 摩擦係数) -> Self {
        let 場面 = 坂の上の二段の箱の場面::生成する(傾きの正接, 摩擦);
        Self {
            工程: 場面.工程,
            台帳: 場面.台帳,
            休止を見る箱の識別子: vec![場面.下の箱, 場面.上の箱],
            終えた刻みの数: 0,
        }
    }

    /// 1刻み進め、その刻みの細分ごとのバッチを返す。進める工程のエラーは試験の場面の組み立ての誤りであり落とす。
    pub(super) fn 一刻み進める(&mut self) -> Vec<接触拘束の二つのバッチ> {
        let Ok(細分ごと) = self.工程.一刻み進めて細分ごとのバッチを返す(&mut self.台帳) else {
            panic!("刻み {} で一刻み進めるエラー", self.終えた刻みの数);
        };
        self.終えた刻みの数 += 1;
        細分ごと
    }

    /// ここまでに終えた刻みの数。進める前に読めば、これから進める刻みの0から数えた番号になる。
    pub(super) fn 終えた刻みの数(&self) -> usize {
        self.終えた刻みの数
    }

    /// 休止を見る箱が全部休止しているか。
    pub(super) fn 全部の箱が休止しているか(&self) -> bool {
        self.休止を見る箱の識別子
            .iter()
            .all(|&id| self.台帳.参照する(id).is_ok_and(|剛体| 剛体.実行状態().休止しているか()))
    }

    /// 計器が溜めた求解の内訳を読み、溜めを空にする。走行の始めに1度呼ぶと、そこから数え始める。
    pub(super) fn 定まった解の内訳を読む(&self) -> Vec<単精度の解の内訳> {
        self.工程.解法.計器.定まった解の内訳を数え始めて溜まった分を読む()
    }

    /// 受理の判定を通った連立方程式の接線変位の長さの最大を読み、溜めを零へ戻す。
    pub(super) fn 接線変位の長さの最大を読んで零に戻す(&self) -> f32 {
        self.工程.解法.計器.接線変位の長さの最大を読んで零に戻す()
    }

    /// 粘着の候補が解けなかった延べ数と、そのうち表現の精度が不足した延べ数。
    pub(super) fn 解けなかった延べ数と精度不足の延べ数(&self) -> (usize, usize) {
        let 結末 = self.工程.解法.計器.解けなかった結末();
        (結末.延べ数(), 結末.表現の精度が不足した延べ数())
    }

    /// 剛体の台帳と、休止を見る箱の識別子。箱1つずつの状態を読む計器が使う。
    pub(super) fn 台帳と箱の識別子(&self) -> (&剛体の台帳, &[剛体の識別子]) {
        (&self.台帳, &self.休止を見る箱の識別子)
    }
}
