//! あいだに定まった全部の求解について、固有値を最大の固有値で割った相対値がどの桁に何本居るかと、求解ごとの
//! 最も広い隙間が重なる帯を綴る。坂の側は
//! `crates/blitz_sim/src/contact/scene/numeric_contract_record/tolerance_dependence/eigen_direction_switch/eigen_relative_spread_record.rs` が別に綴る。
//! 剛体どうしの接触を別に測るのは、こちらの連立方程式が2つの動く剛体の自由度12を持ち、階数不足の向きの本数が
//! 剛体と静的世界の接触(自由度6)と違うためである。合否は判定しない。
//! 実行は `cargo test -p blitz_sim --release 固有値の相対分布_剛体どうし -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::stacked_slope_fixture::坂の上の二段の箱の場面;
use super::super::tower_fixture::箱の塔の場面を作る;
use crate::contact::friction_coefficient::摩擦係数;
use crate::contact::normal_tangential_system::固有値を最大で割った相対値の広がり;

const 塔の段数: u16 = 10;
const 二段の箱の傾きの正接: f32 = 0.55;
const 綴る刻みの数: usize = 1;

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 固有値の相対分布_剛体どうしの二場面を綴る() {
    塔の相対分布を綴る();
    二段の箱の相対分布を綴る();
}

fn 塔の相対分布を綴る() {
    let (mut 工程, mut 台帳, _, _) = 箱の塔の場面を作る(塔の段数, false);
    工程.解法.計器.定まった解の内訳を数え始めて溜まった分を読む();
    let mut 広がり = 固有値を最大で割った相対値の広がり::零から始める();
    for 刻み in 0..綴る刻みの数 {
        let Ok(_) = 工程.一刻み進めて細分ごとのバッチを返す(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        for 内訳 in 工程.解法.計器.定まった解の内訳を数え始めて溜まった分を読む() {
            広がり.一回の求解を数える(&内訳);
        }
    }
    println!("  要約 [箱{塔の段数}段の塔_本番の適用規則] {}", 広がり.綴り());
}

fn 二段の箱の相対分布を綴る() {
    let Ok(摩擦) = 摩擦係数::生成する(0.6) else {
        panic!("摩擦係数を作れない");
    };
    let mut 場面 = 坂の上の二段の箱の場面::生成する(二段の箱の傾きの正接, 摩擦);
    場面.工程.解法.計器.定まった解の内訳を数え始めて溜まった分を読む();
    let mut 広がり = 固有値を最大で割った相対値の広がり::零から始める();
    for 刻み in 0..綴る刻みの数 {
        let Ok(_) = 場面.工程.一刻み進めて細分ごとのバッチを返す(&mut 場面.台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        for 内訳 in 場面.工程.解法.計器.定まった解の内訳を数え始めて溜まった分を読む() {
            広がり.一回の求解を数える(&内訳);
        }
    }
    println!("  要約 [坂の上の二段の箱_正接{二段の箱の傾きの正接}_本番の適用規則] {}", 広がり.綴り());
}
