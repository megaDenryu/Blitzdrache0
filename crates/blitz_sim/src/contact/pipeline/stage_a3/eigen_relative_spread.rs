//! Issue #103の段階A3の計測1のうち、剛体どうしの接触(箱10段の塔と坂の上の2段の箱)の側の計器。1刻み(細分16本)の
//! あいだに定まった全部の求解について、固有値を最大の固有値で割った相対値がどの桁に何本居るかと、求解ごとの
//! 最も広い隙間が重なる帯を綴る。坂の側は
//! `crates/blitz_sim/src/contact/scene/numeric_contract_record/tolerance_dependence/eigen_direction_switch/eigen_relative_spread_record.rs` が別に綴る。
//! 剛体どうしの接触を別に測るのは、こちらの連立方程式が2つの動く剛体の自由度12を持ち、階数不足の向きの本数が
//! 剛体と静的世界の接触(自由度6)と違うためである。合否は判定しない。
//! 実行は `cargo test -p blitz_sim --release 固有値の相対分布_剛体どうし -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::body_scene_run::剛体どうしの場面の走行;
use crate::contact::friction_coefficient::摩擦係数;
use crate::contact::normal_tangential_system::{固有値を最大で割った相対値の広がり, 試験の許容差の当て方};

const 塔の段数: u16 = 10;
const 二段の箱の傾きの正接: f32 = 0.55;
const 綴る刻みの数: usize = 1;

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 固有値の相対分布_剛体どうしの二場面を綴る() {
    塔の相対分布を綴る();
    二段の箱の相対分布を綴る();
}

// 1つの走行を刻みの数だけ進め、定まった全部の求解の固有値の相対値を数えて綴る。
fn 一つの走行の相対分布を綴る(見出し: &str, mut 走行: 剛体どうしの場面の走行) {
    走行.定まった解の内訳を読む();
    let mut 広がり = 固有値を最大で割った相対値の広がり::零から始める();
    for _ in 0..綴る刻みの数 {
        走行.一刻み進める();
        for 内訳 in 走行.定まった解の内訳を読む() {
            広がり.一回の求解を数える(&内訳);
        }
    }
    println!("  要約 [{見出し}] {}", 広がり.綴り());
}

fn 塔の相対分布を綴る() {
    一つの走行の相対分布を綴る(
        &format!("箱{塔の段数}段の塔_本番の適用規則"),
        剛体どうしの場面の走行::箱の塔から始める(塔の段数, 試験の許容差の当て方::本番と同じ当て方()),
    );
}

fn 二段の箱の相対分布を綴る() {
    let Ok(摩擦) = 摩擦係数::生成する(0.6) else {
        panic!("摩擦係数を作れない");
    };
    一つの走行の相対分布を綴る(
        &format!("坂の上の二段の箱_正接{二段の箱の傾きの正接}_本番の適用規則"),
        剛体どうしの場面の走行::坂の上の二段の箱から始める(二段の箱の傾きの正接, 摩擦),
    );
}
