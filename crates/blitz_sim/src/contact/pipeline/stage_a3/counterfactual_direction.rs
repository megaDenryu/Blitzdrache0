//! Issue #103の段階A5の計測15が、固有の向き1本について3つの判定の答えと3つの量を読む工程(試験と計器の専用)。
//! 判定はどれも解の内訳が既に持つ量だけから決まるため、この工程は固有分解を組み直さない。
//! 数を畳む側(`counterfactual_tally`)から分けているのは、あちらが複数の求解を通した度数を溜める型であり、
//! こちらが向き1本を読むだけの工程だからである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use crate::contact::normal_tangential_system::{単精度の固有の向きの内訳, 単精度の解の内訳};

// 段階A5が出発点として選んだ2つの値。
const 相対比の出発点: f32 = 2.1e-5;
const 増分の倍率の出発点: f32 = 100.0;

/// 固有の向き1本を、本番・相対固有値の枝・連言の枝の3つが捨てるか。偽の固有値の向きはこの口へ渡さない。
pub(super) struct 三つの判定の答え {
    pub(super) 本番が捨てる: bool,
    pub(super) 相対固有値の枝が捨てる: bool,
    pub(super) 連言の枝が捨てる: bool,
}

impl 三つの判定の答え {
    pub(super) fn 内訳と向きから読む(内訳: &単精度の解の内訳, 向き: &単精度の固有の向きの内訳) -> Self {
        let 本番が捨てる = 向き.右辺の射影.abs() <= 向き.許容差の射影;
        let 相対固有値の枝が捨てる = 相対固有値(内訳, 向き) <= 相対比の出発点;
        let 正当性が在る = 相対固有値の枝が捨てる || 正規化した増分(内訳, 向き) >= 増分の倍率の出発点;
        Self {
            本番が捨てる,
            相対固有値の枝が捨てる,
            連言の枝が捨てる: 本番が捨てる && 正当性が在る,
        }
    }
}

/// この向きの固有値を最大の固有値で割った相対比。
pub(super) fn 相対固有値(内訳: &単精度の解の内訳, 向き: &単精度の固有の向きの内訳) -> f32 {
    if 内訳.最大の固有値 > 0.0 {
        向き.固有値 / 内訳.最大の固有値
    } else {
        0.0
    }
}

/// この向きを解いたときの増分を、右辺をいちばん硬い向きで解いたときの増分で割った値。
pub(super) fn 正規化した増分(内訳: &単精度の解の内訳, 向き: &単精度の固有の向きの内訳) -> f32 {
    let 分母 = 内訳.右辺をいちばん硬い向きで解いたときの増分();
    if 分母 > 0.0 && 向き.固有値 > 0.0 {
        (向き.右辺の射影 / 向き.固有値).abs() / 分母
    } else {
        0.0
    }
}
