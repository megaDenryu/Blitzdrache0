//! Issue #103の段階A5の計測10と計測14のうち、箱10段の塔の側の計器。本番の右辺の側の判定の代わりに置く3つの規則を
//! 本番と並べ、全部の箱が休止する刻みが本番の41から後退しないかを読む。
//! あわせて、その枝が捨てた向きを2つに分けて数える。正規化した増分が100以上の向き(壊す向き)と、100未満の向き
//! (無害な向き)である。無害な向きを何本捨て、その増分の最大がどれだけかが、「帯が開かないことの害」の実測になる。
//! 帯が開かないとは「壊す向きを全部捨てる線を引くと、無害な向きも何本か一緒に捨てる」ことであり、一緒に捨てた
//! 向きの増分が小さければ害は無い。段階A5の計測5はその本数も増分も数えていなかった。
//! 休止の刻みだけを綴る`tower_rest_step`から分けているのは、こちらが捨てた向きの内訳も同じ走行から数えるためである。
//! 合否は判定しない。本番の判定と閾値と既定は1つも変えていない。
//! 実行は `cargo test -p blitz_sim --release 本番の代わりの捨て方の塔 -- --ignored --nocapture --test-threads=1` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::body_scene_run::剛体どうしの場面の走行;
use crate::contact::normal_tangential_system::{
    単精度の解の内訳, 擬似逆が右辺の向きを捨てる判定の当て方, 試験の許容差の当て方
};
use crate::contact::symmetric_system::{擬似逆が固有の向きを捨てた理由, 本番の代わりに置く右辺の向きの捨て方};

const 塔の段数: u16 = 10;
const 綴る刻みの数: usize = 120;
// 捨てた向きを2つに分ける線。段階A5の計測5が「壊す向き」と読んだ正規化した増分の下端と同じ値である。
const 壊すと読む正規化した増分の下端: f32 = 100.0;
// 親が出発点として選んだ2つの値。増分の倍率は上の線と同じ値、相対比は偽の固有値の下限を本番の11倍へ上げる値である。
const 増分の倍率の出発点: f32 = 100.0;
const 相対比の出発点: f32 = 2.1e-5;

// 1つの求解で、捨てられた向きを壊す側と無害な側へ分けて数える。無害な側の増分の最大も返す。
fn 一つの求解の捨てた向きを数える(内訳: &単精度の解の内訳) -> (usize, usize, f32) {
    let 硬い向きの増分 = 内訳.右辺をいちばん硬い向きで解いたときの増分();
    let (mut 壊す, mut 無害, mut 無害の増分の最大) = (0, 0, 0.0f32);
    for 向き in &内訳.固有の向きごと {
        if 向き.捨てた理由 != 擬似逆が固有の向きを捨てた理由::右辺が許容差の内側 || 向き.固有値 <= 0.0 {
            continue;
        }
        let 増分 = (向き.右辺の射影 / 向き.固有値).abs();
        let 正規化した増分 = if 硬い向きの増分 > 0.0 {
            増分 / 硬い向きの増分
        } else {
            0.0
        };
        if 正規化した増分 >= 壊すと読む正規化した増分の下端 {
            壊す += 1;
        } else {
            無害 += 1;
            無害の増分の最大 = 無害の増分の最大.max(正規化した増分);
        }
    }
    (壊す, 無害, 無害の増分の最大)
}

fn 一つの適用規則の塔を綴る(見出し: &str, 適用規則: 試験の許容差の当て方) {
    let mut 走行 = 剛体どうしの場面の走行::箱の塔から始める(塔の段数, 適用規則);
    走行.定まった解の内訳を読む();
    let (mut 全部が休止した刻み, mut 壊す, mut 無害, mut 無害の増分の最大) = (None, 0, 0, 0.0f32);
    for _ in 0..綴る刻みの数 {
        let 刻み = 走行.終えた刻みの数();
        走行.一刻み進める();
        for 内訳 in 走行.定まった解の内訳を読む() {
            let (壊す一回, 無害一回, 最大一回) = 一つの求解の捨てた向きを数える(&内訳);
            壊す += 壊す一回;
            無害 += 無害一回;
            無害の増分の最大 = 無害の増分の最大.max(最大一回);
        }
        if 全部が休止した刻み.is_none() && 走行.全部の箱が休止しているか() {
            全部が休止した刻み = Some(刻み);
        }
    }
    let (解けなかった延べ数, _) = 走行.解けなかった延べ数と精度不足の延べ数();
    println!(
        "  V [箱{塔の段数}段の塔_{見出し}] 全部が休止した刻み={全部が休止した刻み:?} 捨てた壊す向き={壊す}本 捨てた無害な向き={無害}本(正規化した増分の最大={無害の増分の最大:.4e}) 解けず{解けなかった延べ数}"
    );
}

fn 本番の代わりの規則の適用規則(捨て方: 本番の代わりに置く右辺の向きの捨て方) -> 試験の許容差の当て方 {
    試験の許容差の当て方::本番と同じ当て方().右辺の向きを捨てる判定を差し替える(
        擬似逆が右辺の向きを捨てる判定の当て方::本番の代わりの規則で捨てる { 捨て方 },
    )
}

