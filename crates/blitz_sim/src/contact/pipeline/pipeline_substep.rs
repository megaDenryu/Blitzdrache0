//! 細分1本の工程(判断19)。衝撃の適用・予測・索引の更新と候補の列挙・接触点集合の生成と履歴の対応付け・島の構築・反復・
//! 速度の再構成・速度段階・休止の判定を、この順で1度ずつ回す。
//! 休止の判定を刻みの末でなくここへ置くのは、判断18の静穏の4条件が細分の末の速度・貫通残差・錨で決まるためである。
//! 刻みの末で1度だけ判定すると、休止までに要る静穏の物理時間が細分数の倍だけ伸び、解法品質の設定が休止の時間意味を変える。
//! 刻み1本の工程(`pipeline_step`)から分けているのは、呼ばれる頻度が細分ごとと刻みごとで違い、扱う状態も細分の中だけの
//! 予測と、刻みを跨ぐ履歴と実行状態に分かれるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」。

