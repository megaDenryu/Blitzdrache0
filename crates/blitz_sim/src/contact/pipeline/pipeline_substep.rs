/// 細分の末で休止の判定を行うかどうか。休止が物理の結果を変えない最適化であること(判断18)を検査する反証の経路が`行わない`を選ぶ。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 休止の判定の実施 {
    行う,
    行わない,
}

impl 剛体の接触の一刻みの工程 {
    /// 細分1本を回す。組み直した島の分割も接触拘束のバッチも工程の中で使い切るため戻り値に出さない。
    pub(super) fn 一細分進める(
        &mut self,
        台帳: &mut 剛体の台帳,
        作用: &mut 刻みの初めに取り出した作用,
        休止の判定: 休止の判定の実施,
    ) -> Result<(), 接触の工程エラー> {
        if let Some(衝撃一覧) = 作用.衝撃を一度だけ取り出す() {
            self.最初の細分の衝撃を適用する(台帳, &衝撃一覧)?;
        }
        let mut 予測の結果 = self.予測して索引を更新する(台帳, 作用)?;
        let mut 対一覧 = Vec::new();
        self.空間.重なりうる形の対を集める(&mut 対一覧)?;
        let mut 候補対一覧 = Vec::new();
        剛体どうしの候補対を絞り込む(&対一覧, 台帳, &mut 候補対一覧)?;
        let mut バッチ =
            接触拘束の二つのバッチを構築する(&self.時間方針, &self.空間, &候補対一覧, &予測の結果.接触点集合を作る配置一覧)?;
        self.履歴.履歴を引き継ぐ(&mut バッチ, &予測の結果.予測の前の配置一覧)?;
        self.直前の島.新しい接触の契機を島へ伝える(&バッチ, 台帳.剛体一覧_mut());
        let 島一覧 = 接触島の一覧を構築する(作用.動的な剛体の識別子一覧(), &mut バッチ, &self.直前の島, 台帳.剛体一覧());
        self.解法.反復と再構成と速度段階を解く(
            self.時間方針.解く品質(),
            self.時間方針.細分の刻み幅(),
            &mut バッチ,
            &島一覧,
            &mut 予測の結果.動的剛体一覧,
            台帳.剛体一覧_mut(),
        )?;
        self.履歴.履歴を置き換える(&バッチ)?;
        if 休止の判定 == 休止の判定の実施::行う {
            self.休止を判定する(台帳, &島一覧, &バッチ);
        }
        self.直前の島.組み直した島で置き換える(島一覧);
        Ok(())
    }

    // この細分が組んだ島ごとに静穏を判定し、静穏の継続時間を細分1本ぶん進めるか零へ戻す(判断18)。
    fn 休止を判定する(&self, 台帳: &mut 剛体の台帳, 島一覧: &[接触島], バッチ: &接触拘束の二つのバッチ) {
        let 細分の刻み幅 = self.時間方針.細分の刻み幅();
        for 島 in 島一覧 {
            let 静穏か = 島.静穏か(バッチ, 台帳.剛体一覧());
            島.休止状態を更新する(静穏か, 細分の刻み幅, 台帳.剛体一覧_mut());
        }
    }

    // 工程2で取り出した衝撃と回転衝撃を、最初の細分の予測の前に1度だけ速度へ足す(判断6)。
    fn 最初の細分の衝撃を適用する(
        &self,
        台帳: &mut 剛体の台帳,
        衝撃一覧: &[(剛体の識別子, crate::rigid_body::一度だけ適用する衝撃)],
    ) -> Result<(), 接触の工程エラー> {
        for &(識別子, 衝撃) in 衝撃一覧 {
            let 剛体 = 台帳.参照する(識別子)?;
            let (配置, 特性, 速度) = (*剛体.配置(), *剛体.質量特性(), 剛体.速度()?);
            let 参加者 = 姿勢自由度の参加者::動的(配置, &特性);
            let 新しい速度 = 衝撃.運動状態へ適用する(速度, 参加者.逆質量(), 参加者.ワールドの逆慣性());
            if 新しい速度 != 速度 {
                self.直前の島
                    .契機を受けて島ごと起こす(識別子, 休止から起きた理由::作用の投入, 台帳.剛体一覧_mut());
            }
            台帳.書き換える(識別子)?.配置と速度を書き換える(配置, 新しい速度)?;
        }
        Ok(())
    }

    // 起きている動的剛体を予測して動く形の空間索引を更新し、接触点集合の生成が読む配置と直方体の一覧を作る(判断8・11)。
    fn 予測して索引を更新する(
        &mut self,
        台帳: &剛体の台帳,
        作用: &刻みの初めに取り出した作用,
    ) -> Result<細分の予測の結果, 接触の工程エラー> {
        let mut 結果 = 細分の予測の結果::空から始める();
        for 剛体 in 台帳.剛体一覧() {
            let 識別子 = 剛体.識別子();
            let 半分の長さ = self.空間.形状を参照する(識別子)?;
            let 運動種別::動的 { 運動状態, .. } = 剛体.運動種別() else {
                結果.動かない剛体を足す(識別子, *剛体.配置(), 直方体を組む(剛体.配置(), 半分の長さ)?);
                continue;
            };
            if !剛体.実行状態().起きているか() {
                結果.動かない剛体を足す(識別子, *剛体.配置(), 直方体を組む(剛体.配置(), 半分の長さ)?);
                continue;
            }
            let 入力 = 作用.一刻みの入力(識別子);
            let (前の状態, 予測, 予測の運動状態) = self.解法.動的剛体を予測する(剛体.配置(), 運動状態, 剛体.質量特性(), &入力);
            let 大域箱 = 始点と終点の直方体から大域の箱を求める(剛体.配置(), 予測.配置(), 半分の長さ)?;
            self.空間.形の箱を更新する(識別子, &大域箱)?;
            let 直方体 = 直方体を組む(予測.配置(), 半分の長さ)?;
            結果.予測した剛体を足す(
                細分の動的剛体 {
                    識別子,
                    前の状態,
                    予測,
                    予測の運動状態,
                },
                直方体,
            );
        }
        Ok(結果)
    }
}
