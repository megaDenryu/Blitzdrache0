//! 混合連立の受理の判定が数値の契約を破った件数を、破った契約ごとに数える計器(判断13の2026-09-12の実装の細目の(3)。
//! 試験と計器の専用)。退避の件数・理由・残差を δ の倍率ごとに記録へ残すために要る。合否は判定しない。
//! 解法の計器(`solver_gauge`)から分けているのは、こちらが受理の判定だけを数える受け皿であり、あちらが適用規則と
//! 解いた回数と解けなかった延べ数を束ねる型だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use crate::contact::normal_tangential_system::{受理の契約を破った理由, 混合連立の受理の結果};

/// 受理の判定が数値の契約を破った件数の、契約ごとの内訳。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 受理の破れの数え {
    積まなかった点の残差: usize,
    積んだ接線の行の残差: usize,
    相補条件: usize,
    捨てた成分を戻した残差: usize,
    残差と許容差の比の最大: f32, // 破った件のうち |残差| ÷ 許容差 の最大。相補条件の破れは比を持たない
}

impl 受理の破れの数え {
    pub(super) fn 零から始める() -> Self {
        Self {
            積まなかった点の残差: 0,
            積んだ接線の行の残差: 0,
            相補条件: 0,
            捨てた成分を戻した残差: 0,
            残差と許容差の比の最大: 0.0,
        }
    }

    /// 受理の判定の結末を1件数える。受理した結末と円錐を超えた結末は数えない。
    pub(super) fn 一件を数える(&mut self, 結果: &混合連立の受理の結果) {
        let 混合連立の受理の結果::数値の契約を破った(理由) = 結果 else {
            return;
        };
        match 理由 {
            受理の契約を破った理由::積まなかった点の残差が許容差を超えた { 残差, .. } => {
                self.積まなかった点の残差 += 1;
                self.比の最大を更新する(残差.許容差に対する比());
            }
            受理の契約を破った理由::積んだ接線の行の残差が許容差を超えた { 残差, .. } => {
                self.積んだ接線の行の残差 += 1;
                self.比の最大を更新する(残差.許容差に対する比());
            }
            受理の契約を破った理由::相補条件を満たさない => self.相補条件 += 1,
            受理の契約を破った理由::捨てた成分を戻した残差が許容差を超えた { 残差, .. } => {
                self.捨てた成分を戻した残差 += 1;
                self.比の最大を更新する(残差.許容差に対する比());
            }
        }
    }

    /// 数値の契約を破った延べ数。
    pub(super) fn 延べ数(&self) -> usize {
        self.積まなかった点の残差 + self.積んだ接線の行の残差 + self.相補条件 + self.捨てた成分を戻した残差
    }

    /// 表へ綴る形。
    pub(super) fn 綴り(&self) -> String {
        format!(
            "受理の破れ{}(A積まなかった点{} B1積んだ接線の行{} B2相補条件{} B4捨てた成分{} 比の最大{:.3})",
            self.延べ数(),
            self.積まなかった点の残差,
            self.積んだ接線の行の残差,
            self.相補条件,
            self.捨てた成分を戻した残差,
            self.残差と許容差の比の最大
        )
    }

    fn 比の最大を更新する(&mut self, 比: f32) {
        self.残差と許容差の比の最大 = self.残差と許容差の比の最大.max(比);
    }
}
