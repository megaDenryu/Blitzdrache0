//! 剛体と静的世界の接触点集合の連立を組む工程と、解いた増分から仮の乗数の集まりを組む工程(判断12・13)。
//! 解く工程(`pipeline_solve_static`)から分けているのは、こちらが接触点集合の走査1回で終わる前後の工程であるのに対し、
//! あちらが解いて円錐を判定して確定する工程だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12」「判断13」。

use blitz_collision::contact_set::接触点の上限;

