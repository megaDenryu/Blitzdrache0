//! 解法が持つ計器(判断12・判断13)。本番の構成では何も持たず何も数えず、試験の構成だけが、許容差の当て方と、
//! 有効集合の探索が解いた連立の回数の累計と、粘着の候補が解けなかった結末の延べ数を持つ。
//! 2つの構成で同じ型名と同じメソッドを置くのは、解く工程の側に構成ごとの分岐を1つも書かないためである
//! (本番の構成ではどのメソッドも空になり、最適化で消える)。
//! 束ねている欄はどれも「試験の構成だけが持ち、場面を組んでから読むまで生き、本番の解には1ビットも効かない」という
//! 同じ寿命と同じ存在理由を持つ。数える口と当て方を貸す口を自分で持ち、溜まった値を外へ出す読む口は子モジュール
//! `readings`が持つ。求解ごとの解の内訳を溜める受け皿は子モジュール`solved_breakdown_tally`が持つ。
//! 本番の構成の中身は子モジュール`production`が持つ。
//! 注意: 本番と違う許容差の当て方を差し替えてよいのは数値契約の診断の計器だけである。許容差は解法の取り決めであり、
//! 場面ごとに変える値ではない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#[cfg(test)]
use std::cell::{Cell, RefCell};

#[cfg(not(test))]
mod production;
#[cfg(test)]
mod readings;
#[cfg(test)]
mod solved_breakdown_tally;

#[cfg(test)]
use super::acceptance_breach_reading::受理の破れの読み取り;
#[cfg(test)]
use super::acceptance_tally::受理の破れの数え;
#[cfg(test)]
use crate::contact::normal_tangential_system::{
    接触点集合の法線と接線の連立, 混合連立の受理の結果, 相補条件を満たす有効集合を探した結末, 試験の許容差の当て方, 部分集合を解いた回数,
};
#[cfg(test)]
use solved_breakdown_tally::定まった解の内訳の数え;

/// 解法が持つ計器。
#[cfg(test)]
pub(super) struct 解法の計器 {
    許容差の当て方: 試験の許容差の当て方,
    解いた回数の累計: Cell<部分集合を解いた回数>,
    粘着の候補が解けなかった延べ数: Cell<usize>,
    表現の精度が不足した延べ数: Cell<usize>,
    受理の破れ: Cell<受理の破れの数え>,
    受理の判定の履歴: RefCell<Vec<(混合連立の受理の結果, Option<受理の破れの読み取り>)>>, // 数えた順に全部の結末を積む。診断の計器が刻みごとに読んで空にする
    定まった解の内訳の数え: RefCell<定まった解の内訳の数え>,                              // 印を立てた計器だけが溜める。印が無い実行では1件も数えない
    接線変位の長さの最大: Cell<f32>, // 受理の判定を通った連立の |C_t| の最大。接線の雑音の床を測る計器が刻みごとに読んで零に戻す
}

/// 本番の構成の解法の計器。何も持たず、何も数えない。
#[cfg(not(test))]
pub(super) struct 解法の計器;

#[cfg(test)]
impl 解法の計器 {
    pub(super) fn 零から始める() -> Self {
        Self {
            許容差の当て方: 試験の許容差の当て方::本番と同じ当て方(),
            解いた回数の累計: Cell::new(部分集合を解いた回数::零()),
            粘着の候補が解けなかった延べ数: Cell::new(0),
            表現の精度が不足した延べ数: Cell::new(0),
            受理の破れ: Cell::new(受理の破れの数え::零から始める()),
            受理の判定の履歴: RefCell::new(Vec::new()),
            定まった解の内訳の数え: RefCell::new(定まった解の内訳の数え::零から始める()),
            接線変位の長さの最大: Cell::new(0.0),
        }
    }

    /// 1行も積んでいない連立。差し替えた当て方を持たせる。
    pub(super) fn 空の連立を組む(&self, 点の数: usize) -> 接触点集合の法線と接線の連立 {
        接触点集合の法線と接線の連立::点の数と試験の許容差の当て方から空で始める(点の数, self.許容差の当て方)
    }

    /// 粘着の候補を1回解いた結末と、そのあいだに解いた連立の回数を数える。
    pub(super) fn 粘着の候補の求解を数える(
        &self, 結末: &相補条件を満たす有効集合を探した結末, 回数: 部分集合を解いた回数
    ) {
        self.解いた回数の累計.set(self.解いた回数の累計.get().足す(回数));
        match 結末 {
            相補条件を満たす有効集合を探した結末::有効集合が定まった { .. } => {}
            相補条件を満たす有効集合を探した結末::相補条件を満たす有効集合が無い => {
                self.粘着の候補が解けなかった延べ数.set(self.粘着の候補が解けなかった延べ数.get() + 1);
            }
            相補条件を満たす有効集合を探した結末::表現の精度が不足した => {
                self.粘着の候補が解けなかった延べ数.set(self.粘着の候補が解けなかった延べ数.get() + 1);
                self.表現の精度が不足した延べ数.set(self.表現の精度が不足した延べ数.get() + 1);
            }
        }
    }

    /// 混合連立の受理の判定の結末を数える。数値の契約を破った結末は退避の枝であり、粘着の候補が解けなかった延べ数にも足す。
    pub(super) fn 受理の判定を数える(&self, 結果: &混合連立の受理の結果, 連立: &接触点集合の法線と接線の連立) {
        self.受理の判定の履歴
            .borrow_mut()
            .push((*結果, 受理の破れの読み取り::結末と連立から読む(結果, 連立)));
        self.定まった解の内訳の数え.borrow_mut().一件を数える(連立);
        self.接線変位の長さの最大
            .set(self.接線変位の長さの最大.get().max(連立.全部の点の接線変位の長さの最大()));
        if !結果.退避の枝へ落ちるか() {
            return;
        }
        self.粘着の候補が解けなかった延べ数.set(self.粘着の候補が解けなかった延べ数.get() + 1);
        let mut 数え = self.受理の破れ.get();
        数え.一件を数える(結果);
        self.受理の破れ.set(数え);
    }

    /// 試験と計器だけが読む口。当て方を本番と違うものへ差し替える。
    pub(super) fn 許容差の当て方を差し替える(&mut self, 当て方: 試験の許容差の当て方) {
        self.許容差の当て方 = 当て方;
    }
}
