//! 剛体の接触の一刻みの工程の単体試験(判断19)。細分数に依らない運動量の変化を固定する。

use blitz_math::{ニュートン, ニュートン秒, 力, 衝撃};

use super::pipeline_fixture::{テスト工程を作る, 基本刻みの秒};

#[test]
fn 一定の力を加えた運動量の変化は細分数に依らず基本刻みと力の積である() {
    for 細分の数 in [4u32, 8, 16] {
        let (mut 工程, mut 台帳, id) = テスト工程を作る(細分の数);
        let f = 力::成分から生成する(ニュートン::生成する(6.0), ニュートン::生成する(0.0), ニュートン::生成する(0.0));
        let Ok(()) = 台帳.重心へ力を加える(id, f) else {
            panic!();
        };
        let Ok(()) = 工程.一刻み進める(&mut 台帳) else {
            panic!();
        };
        let Ok(剛体) = 台帳.参照する(id) else {
            panic!();
        };
        let Ok(速度) = 剛体.速度() else {
            panic!();
        };
        let 速度x = 速度.並進速度().x().値();
        let 期待 = 6.0 * 基本刻みの秒 / 2.0;
        assert!((速度x - 期待).abs() < 1.0e-5, "細分数{細分の数}で速度{速度x} 期待{期待}");
    }
}

