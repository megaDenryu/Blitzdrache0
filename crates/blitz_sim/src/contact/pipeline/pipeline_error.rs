//! 接触の工程で発生する型付きエラー(判断19)。

use thiserror::Error;

use blitz_collision::dynamic_index::{動く形の空間索引の問い合わせエラー, 動く形の空間索引の操作エラー};
use blitz_collision::shape::直方体の生成エラー;
use blitz_math::方向エラー;

use crate::contact::generation_error::接触拘束の生成エラー;
use crate::contact::history::接触の履歴エラー;
use crate::rigid_body::{剛体の識別子, 剛体エラー, 運動種別の遷移エラー};

#[derive(Debug, Error)]
pub enum 接触の工程エラー {
    #[error("剛体エラー: {0}")]
    剛体エラー(#[from] 剛体エラー),

    #[error("運動種別の遷移エラー: {0}")]
    運動種別の遷移エラー(#[from] 運動種別の遷移エラー),

    #[error("接触拘束の生成エラー: {0}")]
    接触拘束の生成エラー(#[from] 接触拘束の生成エラー),

    #[error("接触の履歴エラー: {0}")]
    接触の履歴エラー(#[from] 接触の履歴エラー),

    #[error("空間索引の操作エラー: {0}")]
    空間索引の操作エラー(#[from] 動く形の空間索引の操作エラー),

    #[error("空間索引の問い合わせエラー: {0}")]
    空間索引の問い合わせエラー(#[from] 動く形の空間索引の問い合わせエラー),

    #[error("剛体 {識別子:?} の形状が登録されていない")]
    形状が登録されていない { 識別子: 剛体の識別子 },

    #[error("剛体 {識別子:?} の材質が登録されていない")]
    材質が登録されていない { 識別子: 剛体の識別子 },

    #[error("直方体の生成エラー: {0}")]
    直方体の生成エラー(#[from] 直方体の生成エラー),

    #[error("クォータニオンエラー: {0}")]
    クォータニオンエラー(#[from] blitz_math::クォータニオンエラー),

    #[error("方向エラー: {0}")]
    方向エラー(#[from] 方向エラー),

    #[error("接触点集合の問い合わせエラー: {0}")]
    接触点集合の問い合わせエラー(#[from] blitz_collision::contact_set::接触点集合の問い合わせエラー),
}
