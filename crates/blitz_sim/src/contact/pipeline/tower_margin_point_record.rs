//! 箱10段の塔で、接触生成の余白の内側の点(符号付き貫通量が負の点)が非貫通の連立へどう効いたかを記録する計器(判断11・12・13)。
//! 担当するのは、受入条件が落ちる刻みの前後で、選んだ1組の剛体の接触点集合について、細分ごとに接触点1つずつの
//! 符号付き貫通量・法線のラグランジュ乗数・有効集合への参加(法線反力の有無)・静止摩擦の錨の置き直しを綴ることである。
//! 合否は判定しない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12」。

#![cfg(test)]

use super::tower_fixture::箱の塔の場面を作る;
use crate::rigid_body::{剛体の台帳, 剛体の識別子};

const 綴り始める刻み: usize = 103;
const 綴り終える刻み: usize = 107;
const 綴る第1の剛体の添字: usize = 3;
const 綴る第2の剛体の添字: usize = 4;

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 塔の余白の内側の点が連立へどう効いたかを綴る() {
    let (mut 工程, mut 台帳, 箱id一覧, _) = 箱の塔の場面を作る(10, false);
    for 刻み in 0..=綴り終える刻み {
        let Ok(細分ごと) = 工程.一刻み進めて細分ごとのバッチを返す(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        if 刻み < 綴り始める刻み {
            continue;
        }
        println!("--- 刻み {刻み} 高さ {:?}", 各段の重心の高さ(&台帳, &箱id一覧));
        for (細分, バッチ) in 細分ごと.iter().enumerate() {
            for 拘束 in バッチ.剛体どうしの接触拘束() {
                let 引数 = 拘束.引数();
                if (引数.剛体a.配列添字(), 引数.剛体b.配列添字()) != (綴る第1の剛体の添字, 綴る第2の剛体の添字) {
                    continue;
                }
                println!(
                    "  細分 {細分:2} 特徴 {:?} 符号付き貫通量 {:+.7} 法線の乗数 {:.6e} 有効集合 {} 錨の置き直し {} 滑走 {}",
                    引数.特徴の識別,
                    引数.生成時の符号付き貫通量.長さ().値(),
                    拘束.法線のラグランジュ乗数().値(),
                    拘束.法線のラグランジュ乗数().値() > 0.0,
                    拘束.静止摩擦の解の状態().錨を置き直したか(),
                    拘束.静止摩擦の解の状態().滑走中か(),
                );
            }
        }
    }
}

fn 各段の重心の高さ(台帳: &剛体の台帳, 箱id一覧: &[剛体の識別子]) -> Vec<f32> {
    箱id一覧
        .iter()
        .map(|&id| {
            let Ok(剛体) = 台帳.参照する(id) else {
                panic!("箱の参照に失敗した: {id:?}");
            };
            剛体.配置().重心の位置().y().値()
        })
        .collect()
}
