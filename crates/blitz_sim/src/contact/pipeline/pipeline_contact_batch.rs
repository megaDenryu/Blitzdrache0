pub fn 接触拘束の二つのバッチを構築する(
    方針: &接触の品質と時間方針,
    空間: &接触の空間と世界,
    候補対一覧: &[剛体どうしの候補対],
    配置一覧: &[接触点集合を作る配置],
    剛体一覧: &mut [剛体],
) -> Result<接触拘束の二つのバッチ, 接触の工程エラー> {
    let mut 組み立て = 方針.バッチ組み立て器を作る(候補対一覧.len());
    for 対 in 候補対一覧 {
        剛体どうしの接触を積む(対, 空間, 配置一覧, 剛体一覧, &mut 組み立て)?;
    }
    for 置いた配置 in 配置一覧 {
        for (相手, 静的箱) in 空間.静的世界の相手一覧() {
            剛体と静的世界の接触を積む(置いた配置, 空間, 相手, 静的箱, &mut 組み立て)?;
        }
    }
    let mut バッチ = 組み立て.二つのバッチを組み立てる();
    バッチ.鍵の昇順へ並べ替える();
    Ok(バッチ)
}

fn 剛体どうしの接触を積む(
    対: &剛体どうしの候補対,
    空間: &接触の空間と世界,
    配置一覧: &[接触点集合を作る配置],
    剛体一覧: &mut [剛体],
    組み立て: &mut 接触拘束のバッチの組み立て,
) -> Result<(), 接触の工程エラー> {
    let (id_a, id_b) = (対.小さい方の剛体(), 対.大きい方の剛体());
    let Some(aの配置) = 配置一覧.iter().find(|置いた| 置いた.識別子 == id_a) else {
        return Ok(());
    };
    let Some(bの配置) = 配置一覧.iter().find(|置いた| 置いた.識別子 == id_b) else {
        return Ok(());
    };
    let 問い = 直方体どうしの接触点集合の問い合わせ::二つの直方体から生成する(&aの配置.直方体, &bの配置.直方体);
    let 二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) = 問い.二つの直方体の重なりの接触点集合を求める()?
    else {
        return Ok(());
    };
    for &id in &[id_a, id_b] {
        if 剛体一覧.get(id.配列添字()).is_some_and(|剛体| 剛体.実行状態().休止しているか()) {
            剛体を起こす(id, 剛体一覧, 休止から起きた理由::新しい接触);
        }
    }
    let 参加者a = 接触に参加する剛体::生成する(id_a, aの配置.配置, 空間.材質を参照する(id_a)?, 空間.形の最小の厚みを求める(id_a)?);
    let 参加者b = 接触に参加する剛体::生成する(id_b, bの配置.配置, 空間.材質を参照する(id_b)?, 空間.形の最小の厚みを求める(id_b)?);
    組み立て.剛体どうしの接触点集合を積む(&参加者a, &参加者b, &集合)?;
    Ok(())
}

fn 剛体と静的世界の接触を積む(
    置いた配置: &接触点集合を作る配置,
    空間: &接触の空間と世界,
    相手: &crate::contact::static_world_partner::静的世界の接触相手,
    静的箱: &任意姿勢の直方体,
    組み立て: &mut 接触拘束のバッチの組み立て,
) -> Result<(), 接触の工程エラー> {
    let id = 置いた配置.識別子;
    let 問い = 直方体どうしの接触点集合の問い合わせ::二つの直方体から生成する(&置いた配置.直方体, 静的箱);
    let 二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) = 問い.二つの直方体の重なりの接触点集合を求める()?
    else {
        return Ok(());
    };
    let 参加者 = 接触に参加する剛体::生成する(id, 置いた配置.配置, 空間.材質を参照する(id)?, 空間.形の最小の厚みを求める(id)?);
    組み立て.剛体と静的世界の接触点集合を積む(&参加者, 相手, &集合)?;
    Ok(())
}
