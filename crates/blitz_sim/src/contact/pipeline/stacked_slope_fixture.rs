//! 坂の上に2段に積んだ動的な箱の場面(判断13の2026-09-12の実装の細目の反証(4)(e)。Issue #59の第4段階)。
//! x軸まわりに傾けた静的な剛体の床の上へ、床と同じ姿勢の動的な箱を2つ面で重ねる。上の箱と下の箱の接触は両側の錨が
//! 動的剛体の局所量である単純な面接触であり、坂の場面(剛体と静的世界)と塔(接線の荷重が無い)のどちらも持たない
//! 組み合わせである。工程の組み立て(`contact_test_pipeline_scene`)と分けているのは、こちらが世界に物を置く工程だからである。
//! 床を静的世界の接触相手でなく静的な剛体にするのは、傾けた直方体を試験の工程へ置く口がこちらだけだからである。
//! 幾何: 傾き θ で x軸まわりに回した姿勢 q = (sin(θ/2), 0, 0, cos(θ/2))、面の法線 n = (0, cosθ, sinθ)、下り向き
//! d = (0, −sinθ, cosθ)。床の上面は n·x = 0.5 の面であり、箱の重心は上面から法線の向きへ 0.5 − 初めの食い込み ずつ積む。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_collision::shape::直方体の軸ごとの半分の長さ;
use blitz_math::{キログラム, メートル, ワールド, 位置, 方向};

use super::contact_test_pipeline_scene::{
    確定した細分数, 細分数と摩擦係数を指定して試験の接触の一刻みの工程を組む, 試験の材質
};
use super::pipeline_def::剛体の接触の一刻みの工程;
use crate::contact::friction_coefficient::摩擦係数;
use crate::rigid_body::{剛体の台帳, 剛体の識別子, 姿勢, 質量特性, 運動状態, 運動種別, 配置};

const 床の半分の厚み: f32 = 0.5;
const 箱の半分の長さ: f32 = 0.5;
const 初めの食い込み: f32 = 1.0e-4;

/// 坂の上の2段の箱の場面。
pub(super) struct 坂の上の二段の箱の場面 {
    pub(super) 工程: 剛体の接触の一刻みの工程,
    pub(super) 台帳: 剛体の台帳,
    pub(super) 下の箱: 剛体の識別子,
    pub(super) 上の箱: 剛体の識別子,
    pub(super) 下り向き: 方向<ワールド>,
}

impl 坂の上の二段の箱の場面 {
    /// 本番の細分数16で、傾きの正接と摩擦係数(静止と動を同じ値)を指定して組む。
    pub(super) fn 生成する(傾きの正接: f32, 摩擦: 摩擦係数) -> Self {
        let 余弦 = 1.0 / (1.0 + 傾きの正接 * 傾きの正接).sqrt();
        let 正弦 = 傾きの正接 * 余弦;
        let 半角 = 傾きの正接.atan() / 2.0;
        let Ok(姿勢) = 姿勢::生成する(半角.sin(), 0.0, 0.0, 半角.cos()) else {
            panic!("傾きの姿勢を作れない");
        };
        let Ok(下り向き) = 方向::生成する(0.0, -正弦, 余弦) else {
            panic!("下り向きを作れない");
        };
        let 法線の成分 = [0.0, 余弦, 正弦];
        let mut 台帳 = 剛体の台帳::空();
        let mut 工程 = 細分数と摩擦係数を指定して試験の接触の一刻みの工程を組む(確定した細分数, 摩擦);
        床を置く(&mut 工程, &mut 台帳, 姿勢);
        let 下の箱 = 箱を置く(&mut 工程, &mut 台帳, 姿勢, 法線の成分, 床の半分の厚み + 箱の半分の長さ - 初めの食い込み);
        let 上の箱 = 箱を置く(
            &mut 工程,
            &mut 台帳,
            姿勢,
            法線の成分,
            床の半分の厚み + 3.0 * 箱の半分の長さ - 2.0 * 初めの食い込み,
        );
        Self {
            工程,
            台帳,
            下の箱,
            上の箱,
            下り向き,
        }
    }
}

// 半分の長さ [10, 0.5, 10] の静的な剛体の床を、原点を中心に傾けた姿勢で置く。
fn 床を置く(工程: &mut 剛体の接触の一刻みの工程, 台帳: &mut 剛体の台帳, 姿勢: 姿勢) {
    let Ok(質量) = キログラム::生成する(1000.0) else {
        panic!("床の質量を作れない");
    };
    let Ok(特性) = 質量特性::一様な箱(質量, メートル::生成する(20.0), メートル::生成する(1.0), メートル::生成する(20.0))
    else {
        panic!("床の質量特性を作れない");
    };
    let 零 = メートル::生成する(0.0);
    let 配置 = 配置::生成する(位置::<ワールド>::生成する(零, 零, 零), 姿勢);
    let Ok(id) = 台帳.登録する(配置, 特性, 運動種別::静的) else {
        panic!("床を台帳へ登録できない");
    };
    let Ok(半分) = 直方体の軸ごとの半分の長さ::生成する(
        [メートル::生成する(10.0), メートル::生成する(床の半分の厚み), メートル::生成する(10.0)],
    ) else {
        panic!("床の半分の長さを作れない");
    };
    let Ok(()) = 工程.剛体を登録する(id, &配置, 半分, 試験の材質()) else {
        panic!("床を工程へ登録できない");
    };
}

// 一辺1メートル・質量1キログラムの動的な箱を、原点から法線の向きへ指定の長さの位置へ床と同じ姿勢で置く。
fn 箱を置く(
    工程: &mut 剛体の接触の一刻みの工程,
    台帳: &mut 剛体の台帳,
    姿勢: 姿勢,
    法線の成分: [f32; 3],
    法線の向きの長さ: f32,
) -> 剛体の識別子 {
    let Ok(質量) = キログラム::生成する(1.0) else {
        panic!("箱の質量を作れない");
    };
    let 一辺 = メートル::生成する(2.0 * 箱の半分の長さ);
    let Ok(特性) = 質量特性::一様な箱(質量, 一辺, 一辺, 一辺) else {
        panic!("箱の質量特性を作れない");
    };
    let 重心 = 位置::<ワールド>::生成する(
        メートル::生成する(法線の成分[0] * 法線の向きの長さ),
        メートル::生成する(法線の成分[1] * 法線の向きの長さ),
        メートル::生成する(法線の成分[2] * 法線の向きの長さ),
    );
    let 配置 = 配置::生成する(重心, 姿勢);
    let Ok(id) = 台帳.登録する(配置, 特性, 運動種別::動的で始める(運動状態::静止())) else {
        panic!("箱を台帳へ登録できない");
    };
    let Ok(半分) = 直方体の軸ごとの半分の長さ::生成する([メートル::生成する(箱の半分の長さ); 3]) else {
        panic!("箱の半分の長さを作れない");
    };
    let Ok(()) = 工程.剛体を登録する(id, &配置, 半分, 試験の材質()) else {
        panic!("箱を工程へ登録できない");
    };
    id
}
