//! 坂の上に2段に積んだ動的な箱の場面(判断13の2026-09-12の実装の細目の反証(4)(e)。Issue #59の第4段階)。
//! x軸まわりに傾けた静的な剛体の床の上へ、床と同じ姿勢の動的な箱を2つ面で重ねる。上の箱と下の箱の接触は両側の錨が
//! 動的剛体の局所量である単純な面接触であり、坂の場面(剛体と静的世界)と塔(接線の荷重が無い)のどちらも持たない
//! 組み合わせである。工程の組み立て(`contact_test_pipeline_scene`)と分けているのは、こちらが世界に物を置く工程だからである。
//! 幾何は `stacked_slope_spec` が持つ。床を静的世界の接触相手でなく静的な剛体にするのは、傾けた直方体を試験の
//! 工程へ置く口がこちらだけだからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_collision::shape::直方体の軸ごとの半分の長さ;
use blitz_math::{キログラム, メートル};

use super::contact_test_pipeline_scene::{
    確定した細分数, 細分数と摩擦係数を指定して試験の接触の一刻みの工程を組む, 試験の材質
};
use super::pipeline_def::剛体の接触の一刻みの工程;
use super::stacked_slope_spec::{
    原点, 坂の上の二段の箱の幾何, 床の半分の厚み, 箱の下り向きの半分の長さ, 箱の横向きの半分の長さ, 箱の法線向きの半分の厚み,
};
use crate::contact::friction_coefficient::摩擦係数;
use crate::rigid_body::{剛体の台帳, 剛体の識別子, 姿勢, 質量特性, 運動状態, 運動種別, 配置};

/// 坂の上の2段の箱の場面。
pub(super) struct 坂の上の二段の箱の場面 {
    pub(super) 工程: 剛体の接触の一刻みの工程,
    pub(super) 台帳: 剛体の台帳,
    pub(super) 下の箱: 剛体の識別子,
    pub(super) 上の箱: 剛体の識別子,
    pub(super) 幾何: 坂の上の二段の箱の幾何,
}

impl 坂の上の二段の箱の場面 {
    /// 本番の細分数16で、傾きの正接と摩擦係数(静止と動を同じ値)を指定して組む。
    pub(super) fn 生成する(傾きの正接: f32, 摩擦: 摩擦係数) -> Self {
        let 幾何 = 坂の上の二段の箱の幾何::傾きの正接から生成する(傾きの正接);
        let mut 台帳 = 剛体の台帳::空();
        let mut 工程 = 細分数と摩擦係数を指定して試験の接触の一刻みの工程を組む(確定した細分数, 摩擦);
        床を置く(&mut 工程, &mut 台帳, 幾何.姿勢());
        let 下の箱 = 箱を置く(&mut 工程, &mut 台帳, &幾何, 0);
        let 上の箱 = 箱を置く(&mut 工程, &mut 台帳, &幾何, 1);
        Self {
            工程,
            台帳,
            下の箱,
            上の箱,
            幾何,
        }
    }
}

// 半分の長さ [10, 0.5, 10] の静的な剛体の床を、原点を中心に傾けた姿勢で置く。
fn 床を置く(工程: &mut 剛体の接触の一刻みの工程, 台帳: &mut 剛体の台帳, 姿勢: 姿勢) {
    let Ok(質量) = キログラム::生成する(1000.0) else {
        panic!("床の質量を作れない");
    };
    let Ok(特性) = 質量特性::一様な箱(質量, メートル::生成する(20.0), メートル::生成する(1.0), メートル::生成する(20.0))
    else {
        panic!("床の質量特性を作れない");
    };
    let 配置 = 配置::二段の位置と姿勢から生成する(原点(), 姿勢);
    let Ok(id) = 台帳.登録する(配置, 特性, 運動種別::静的) else {
        panic!("床を台帳へ登録できない");
    };
    let Ok(半分) = 直方体の軸ごとの半分の長さ::生成する(
        [メートル::生成する(10.0), メートル::生成する(床の半分の厚み), メートル::生成する(10.0)],
    ) else {
        panic!("床の半分の長さを作れない");
    };
    let Ok(()) = 工程.剛体を登録する(id, &配置, 半分, 試験の材質()) else {
        panic!("床を工程へ登録できない");
    };
}

// 坂の下り向きに長い平たい直方体(半分の長さ [0.5, 0.25, 1.0] メートル)・質量1キログラムの動的な箱を、指定の段の重心へ
// 床と同じ姿勢で置く。局所のx軸が坂の横向き、y軸が面の法線、z軸が坂の下り向きである。平たくするのは、立方体を2つ積むと
// 転倒の限界の正接が0.5になり検査が見る正接0.55の静止の解が無くなるためである(限界の式は `stacked_slope_spec` に書いた)。
fn 箱を置く(
    工程: &mut 剛体の接触の一刻みの工程, 台帳: &mut 剛体の台帳, 幾何: &坂の上の二段の箱の幾何, 段: u8
) -> 剛体の識別子 {
    let Ok(質量) = キログラム::生成する(1.0) else {
        panic!("箱の質量を作れない");
    };
    let 横の長さ = メートル::生成する(2.0 * 箱の横向きの半分の長さ);
    let 法線向きの厚み = メートル::生成する(2.0 * 箱の法線向きの半分の厚み);
    let 下り向きの長さ = メートル::生成する(2.0 * 箱の下り向きの半分の長さ);
    let Ok(特性) = 質量特性::一様な箱(質量, 横の長さ, 法線向きの厚み, 下り向きの長さ) else {
        panic!("箱の質量特性を作れない");
    };
    let 配置 = 配置::二段の位置と姿勢から生成する(幾何.箱の重心(段), 幾何.姿勢());
    let Ok(id) = 台帳.登録する(配置, 特性, 運動種別::動的で始める(運動状態::静止())) else {
        panic!("箱を台帳へ登録できない");
    };
    let Ok(半分) = 直方体の軸ごとの半分の長さ::生成する([
        メートル::生成する(箱の横向きの半分の長さ),
        メートル::生成する(箱の法線向きの半分の厚み),
        メートル::生成する(箱の下り向きの半分の長さ),
    ]) else {
        panic!("箱の半分の長さを作れない");
    };
    let Ok(()) = 工程.剛体を登録する(id, &配置, 半分, 試験の材質()) else {
        panic!("箱を工程へ登録できない");
    };
    id
}
