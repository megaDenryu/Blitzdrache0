//! `transition_discard_tests` の後退(30刻みの後に最上段の箱の履歴が無い)を読む計器(親の指示による診断)。箱3段の塔を
//! 30刻み進めながら、刻みごとに、最上段と最下段の実行状態(起きている・休止している)と、それぞれを含む接触の履歴の
//! 件数を綴る。休止した島は接触点集合を作らず履歴も残らないため、履歴が無いことが休止によるものかを分ける。合否は判定しない。
//! 実行は `cargo test -p blitz_sim --release 落ちた場面の刻み_箱三段の塔 -- --ignored --nocapture` である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use blitz_math::{ワールド, 方向};

use super::stacked_slope_spec::原点;
use super::tower_fixture::箱の塔の場面を作る;

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 落ちた場面の刻み_箱三段の塔の履歴と休止を綴る() {
    let (mut 工程, mut 台帳, 箱id一覧, _) = 箱の塔の場面を作る(3, false);
    let Ok(上向き) = 方向::<ワールド>::生成する(0.0, 1.0, 0.0) else {
        panic!("上向きを作れない");
    };
    for 刻み in 0..30 {
        let Ok(()) = 工程.一刻み進める(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        let 状態: Vec<String> = 箱id一覧
            .iter()
            .map(|&id| {
                let Ok(剛体) = 台帳.参照する(id) else {
                    panic!("箱が台帳に無い");
                };
                format!(
                    "{}:{} 履歴{}",
                    if 剛体.実行状態().休止しているか() {
                        "休止"
                    } else {
                        "起床"
                    },
                    (剛体.配置().重心の位置() - 原点()).方向に沿う長さ(上向き).値(),
                    工程.遷移した剛体の履歴の件数(id)
                )
            })
            .collect();
        println!("  刻み{刻み} {}", 状態.join(" / "));
    }
}
