//! 再開の契機が島の全部へ、細分1本の中で一括して届くことの検査(判断18。Issue #80が求めた固定)。
//! 剛体を1体ずつ起こす連鎖の実装では通らない形にしてある。連鎖が細分1本で起こせるのは、起きた剛体と直に接触した隣の1体までである。
//! 休止している剛体どうしの対は粗い選別が接触点集合の生成から外すため、隣の隣はその細分ではまだ休止したままになる。
//! 3つ並べた箱の端へ衝撃を加えた細分の末に反対の端まで起きていること、および3つが同じ理由を記録していることを固定する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use blitz_math::{ニュートン秒, 衝撃};

use super::pipeline_def::剛体の接触の一刻みの工程;
use super::side_by_side_fixture::側面で接する箱の列の場面を作る;
use super::substep_rest_judgment::休止の判定の実施;
use crate::rigid_body::{休止から起きた理由, 剛体の台帳, 剛体の識別子};

// 側面で接する2つの箱は、休止の判定が刻みごとだった2026-09-05の実測で735刻みで休止した。判定が細分ごとへ移った後はこれより早い。上限はその値の2倍強に置く。
const 休止を待つ刻み数: usize = 1600;

#[test]
fn 端へ加えた衝撃が細分一本で三つの箱の島の全部を同じ理由で起こす() {
    let (mut 工程, mut 台帳, 箱一覧) = 側面で接する箱の列の場面を作る(3);
    全部が休止するまで進める(&mut 工程, &mut 台帳, &箱一覧);

    let p = 衝撃::成分から生成する(ニュートン秒::生成する(0.0), ニュートン秒::生成する(5.0), ニュートン秒::生成する(0.0));
    let Ok(()) = 台帳.重心へ衝撃を加える(箱一覧[0], p) else {
        panic!("衝撃を加えられなかった");
    };
    let Ok(()) = 工程.構造変更を反映する(&mut 台帳) else {
        panic!("構造変更の反映に失敗した");
    };
    let Ok(mut 作用) = 工程.作用を取り出す(&mut 台帳) else {
        panic!("作用の取り出しに失敗した");
    };
    let Ok(_この細分のバッチ) = 工程.一細分進める(&mut 台帳, &mut 作用, 休止の判定の実施::行う) else {
        panic!("細分1本に失敗した");
    };

    for &識別子 in &箱一覧 {
        let Ok(剛体) = 台帳.参照する(識別子) else {
            panic!("箱の参照に失敗した: {識別子:?}");
        };
        assert!(
            剛体.実行状態().起きているか(),
            "衝撃を受けた島の中に、細分1本の末でまだ休止している箱がある: {識別子:?}"
        );
        assert_eq!(
            剛体.実行状態().直近に休止から起きた理由(),
            Some(休止から起きた理由::作用の投入),
            "島を再開させた契機は衝撃であるのに、別の理由を記録している箱がある: {識別子:?}"
        );
    }
}

fn 全部が休止するまで進める(
    工程: &mut 剛体の接触の一刻みの工程, 台帳: &mut 剛体の台帳, 箱一覧: &[剛体の識別子]
) {
    for 刻み in 0..休止を待つ刻み数 {
        if let Err(誤り) = 工程.一刻み進める(台帳) {
            panic!("刻み {刻み} で一刻み進めるエラー: {誤り:?}");
        }
        let 全部休止 = 箱一覧
            .iter()
            .all(|&識別子| 台帳.参照する(識別子).is_ok_and(|剛体| 剛体.実行状態().休止しているか()));
        if 全部休止 {
            return;
        }
    }
    panic!("{休止を待つ刻み数}刻み以内に側面で接する3つの箱が休止しなかった");
}
