/// 接触に参加する2つの剛体の、この反復の予測と台帳の状態の組。予測を持たない側は動かせない参加者になる。
#[derive(Clone, Copy)]
pub(super) struct 接触の二つの参加者 {
    pub(super) 予測a: Option<予測の状態>,
    pub(super) 予測b: Option<予測の状態>,
}

impl 接触の二つの参加者 {
    pub(super) fn 姿勢自由度の参加者を組む(
        &self,
        台帳a: &剛体,
        台帳b: &剛体,
    ) -> (姿勢自由度の参加者, 姿勢自由度の参加者) {
        (一人を組む(self.予測a, 台帳a), 一人を組む(self.予測b, 台帳b))
    }

    pub(super) fn 二つの補正を適用する(&self, 補正a: &姿勢自由度の補正, 補正b: &姿勢自由度の補正) -> Self {
        Self {
            予測a: self.予測a.map(|予測| 予測.補正を適用する(補正a)),
            予測b: self.予測b.map(|予測| 予測.補正を適用する(補正b)),
        }
    }
}

fn 一人を組む(予測: Option<予測の状態>, 台帳剛体: &剛体) -> 姿勢自由度の参加者 {
    match 予測 {
        Some(予測) => 姿勢自由度の参加者::動的(*予測.配置(), 台帳剛体.質量特性()),
        None => 姿勢自由度の参加者::動かせない(*台帳剛体.配置()),
    }
}

/// 接触点集合の法線だけを1つの連立として解き、2つの参加者それぞれの補正を合計してから配置へ1度だけ適用する。
pub(super) fn 法線だけを同時に解く(
    集合: &mut [剛体と剛体の接触拘束],
    射影の前: 接触の二つの参加者,
    台帳の剛体: (&剛体, &剛体),
) -> 接触の二つの参加者 {
    let (参加者a, 参加者b) = 射影の前.姿勢自由度の参加者を組む(台帳の剛体.0, 台帳の剛体.1);
    let Some(先頭) = 集合.first() else {
        return 射影の前;
    };
    let mut 行一覧 = [先頭.同時解法の一行にする(&参加者a, &参加者b); 接触点の上限];
    for (番号, 拘束) in 集合.iter().enumerate() {
        行一覧[番号] = 拘束.同時解法の一行にする(&参加者a, &参加者b);
    }
    let 解 = 接触点集合の法線の同時解::接触点集合を同時に解く(&行一覧[..集合.len()]);
    let mut 補正の合計a = 姿勢自由度の補正::零();
    let mut 補正の合計b = 姿勢自由度の補正::零();
    for (番号, 拘束) in 集合.iter_mut().enumerate() {
        let 乗数の増分 = 解.一行の乗数の増分(番号);
        補正の合計a = 補正の合計a.合わせる(&行一覧[番号].乗数の増分を第1の参加者の補正へ分配する(乗数の増分));
        補正の合計b = 補正の合計b.合わせる(&行一覧[番号].乗数の増分を第2の参加者の補正へ分配する(乗数の増分));
        拘束.同時解法の乗数の増分を取り込む(&行一覧[番号], 乗数の増分);
    }
    射影の前.二つの補正を適用する(&補正の合計a, &補正の合計b)
}

/// 接触点集合の全部の点から法線の行と接線の行を積んだ連立と、点ごとの接線の行の結果。
pub(super) fn 法線と接線の連立を組む(
    集合: &[剛体と剛体の接触拘束],
    参加者a: &姿勢自由度の参加者,
    参加者b: &姿勢自由度の参加者,
) -> (接触点集合の法線と接線の連立, [静止摩擦の連立へ点を入れた結果; 接触点の上限]) {
    let mut 点を入れた結果 = [静止摩擦の連立へ点を入れた結果::両方が動かせない; 接触点の上限];
    let mut 連立 = 接触点集合の法線と接線の連立::点の数から空で始める(集合.len());
    for (添字, 拘束) in 集合.iter().enumerate() {
        拘束.法線と接線の連立へ法線の一行を積む(添字, &mut 連立, 参加者a, 参加者b);
        点を入れた結果[添字] = 拘束.法線と接線の連立へ接線の一行を積む(添字, &mut 連立, 参加者a, 参加者b);
    }
    (連立, 点を入れた結果)
}
