fn 錨を無視した判定で休止した刻み(判定: &休止の判定) -> Option<usize> {
    let (mut 工程, mut 台帳, 箱id一覧, _) = 箱の塔の場面を作る(2, false);
    let mut 細分の数え = 連続の数え::空();
    for 刻み in 0..600 {
        一刻み進めて錨を無視した静穏を数える(&mut 工程, &mut 台帳, &mut 細分の数え, 判定);
        let 全部休止 = 箱id一覧
            .iter()
            .all(|&id| 台帳.参照する(id).is_ok_and(|剛体| 剛体.実行状態().休止しているか()));
        if 全部休止 {
            return Some(刻み);
        }
    }
    None
}
