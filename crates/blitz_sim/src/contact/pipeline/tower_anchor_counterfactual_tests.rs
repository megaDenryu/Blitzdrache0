fn 錨を無視して静穏か(島: &接触島, バッチ: &接触拘束の二つのバッチ, 剛体一覧: &[剛体]) -> bool {
    for &識別子 in 島.含まれる動的剛体() {
        let Some(剛体) = 剛体一覧.get(識別子.配列添字()) else {
            return false;
        };
        if !剛体.運動が静穏か() {
            return false;
        }
    }
    let 接触余白 = 休止と判定する接触余白().値();
    for 拘束 in 島.剛体と静的世界の接触拘束の区間().スライスを切り出す(バッチ.剛体と静的世界の接触拘束()) {
        let Some(剛体) = 剛体一覧.get(拘束.引数().剛体.配列添字()) else {
            return false;
        };
        let 点a = 剛体.配置().局所点の世界位置(拘束.引数().剛体側の局所接触点);
        let 隔たり = (拘束.引数().静的世界側の接触点 - 点a).方向に沿う長さ(拘束.引数().接触法線).値();
        if -隔たり > 接触余白 {
            return false;
        }
    }
    for 拘束 in 島.剛体どうしの接触拘束の区間().スライスを切り出す(バッチ.剛体どうしの接触拘束()) {
        let 鍵 = 拘束.履歴の鍵();
        let (Some(剛体a), Some(剛体b)) = (剛体一覧.get(鍵.小さい方の剛体().配列添字()), 剛体一覧.get(鍵.大きい方の剛体().配列添字()))
        else {
            return false;
        };
        let 点a = 剛体a.配置().局所点の世界位置(拘束.引数().局所接触点a);
        let 点b = 剛体b.配置().局所点の世界位置(拘束.引数().局所接触点b);
        let 隔たり = (点b - 点a).方向に沿う長さ(拘束.引数().接触法線).値();
        if -隔たり > 接触余白 {
            return false;
        }
    }
    true
}

struct 連続の数え {
    現在: u32,
    最大: u32,
    成立した数: u32,
}

impl 連続の数え {
    fn 空() -> Self {
        Self {
            現在: 0,
            最大: 0,
            成立した数: 0,
        }
    }

    fn 一つ数える(&mut self, 成立したか: bool) {
        if 成立したか {
            self.現在 += 1;
            self.成立した数 += 1;
            self.最大 = self.最大.max(self.現在);
        } else {
            self.現在 = 0;
        }
    }
}

enum 休止の判定 {
    行わない,
    刻みごとに行う,
    細分ごとに行う,
}

fn 一刻み進めて錨を無視した静穏を数える(
    工程: &mut 剛体の接触の一刻みの工程,
    台帳: &mut 剛体の台帳,
    細分の数え: &mut 連続の数え,
    判定: &休止の判定,
) -> bool {
    let Ok(()) = 工程.構造変更を反映する(台帳) else {
        panic!("構造変更の反映に失敗した");
    };
    let Ok(mut 作用) = 工程.作用を取り出す(台帳) else {
        panic!("作用の取り出しに失敗した");
    };
    let mut 刻みの末の静穏 = false;
    for _ in 0..確定した細分数 {
        let Ok(バッチ) = 工程.一細分進める(台帳, &mut 作用) else {
            panic!("細分1本に失敗した");
        };
        let 静穏 = 工程.直前の島.島一覧().iter().all(|島| 錨を無視して静穏か(島, &バッチ, 台帳.剛体一覧()));
        細分の数え.一つ数える(静穏);
        刻みの末の静穏 = 静穏;
        if matches!(判定, 休止の判定::細分ごとに行う) {
            for 島 in 工程.直前の島.島一覧() {
                島.休止状態を更新する(静穏, 台帳.剛体一覧_mut());
            }
        }
    }
    if matches!(判定, 休止の判定::刻みごとに行う) {
        for 島 in 工程.直前の島.島一覧() {
            島.休止状態を更新する(刻みの末の静穏, 台帳.剛体一覧_mut());
        }
    }
    工程.履歴.刻み境界の配置を確定する(台帳.剛体一覧());
    刻みの末の静穏
}

#[test]
#[ignore = "計器。錨の条件を無視した3条件の連続細分数を数える"]
fn 二段の塔で錨を無視した三条件の最大連続細分数を数える() {
    let (mut 工程, mut 台帳, _, _) = 箱の塔の場面を作る(2, false);
    let mut 細分の数え = 連続の数え::空();
    let mut 刻みの数え = 連続の数え::空();
    for _ in 0..600 {
        let 刻みの末 = 一刻み進めて錨を無視した静穏を数える(&mut 工程, &mut 台帳, &mut 細分の数え, &休止の判定::行わない);
        刻みの数え.一つ数える(刻みの末);
    }
    eprintln!("細分: 最大連続={} 成立した細分={} / 9600", 細分の数え.最大, 細分の数え.成立した数);
    eprintln!(
        "刻みの末だけを見た場合(本番の判定と同じ粒度): 最大連続={} 成立した刻み={} / 600",
        刻みの数え.最大, 刻みの数え.成立した数
    );
}

