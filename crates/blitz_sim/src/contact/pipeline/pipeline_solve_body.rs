use crate::contact::body_body_contact::剛体と剛体の接触拘束;
use crate::contact::normal_tangential_system::{混合連立方程式の受理の結果, 相補条件を満たす有効集合を探した結末};
use crate::contact::static_friction::接触点集合の仮の乗数の集まり;
use crate::rigid_body::剛体;

impl 接触の解法ソルバー {
    pub(super) fn 剛体どうしの接触点集合を一回反復する(
        &self,
        集合: &mut [剛体と剛体の接触拘束],
        動的剛体一覧: &mut [細分の動的剛体],
        剛体一覧: &[剛体],
    ) -> Result<(), 接触の工程エラー> {
        let Some(先頭) = 集合.first() else {
            return Ok(());
        };
        let (id_a, id_b) = (先頭.履歴の鍵().小さい方の剛体(), 先頭.履歴の鍵().大きい方の剛体());
        let (接触物性, 滑走中か) = (先頭.引数().接触物性, 先頭.静止摩擦の解の状態().滑走中か());
        let 台帳の剛体 = (台帳から引く(剛体一覧, id_a)?, 台帳から引く(剛体一覧, id_b)?);
        let 射影の前 = 接触の二つの参加者 {
            予測a: 予測を探す(動的剛体一覧, id_a),
            予測b: 予測を探す(動的剛体一覧, id_b),
        };
        let 解いた後 = self.接触点集合を解く(集合, 射影の前, 台帳の剛体, 接触物性, 滑走中か);
        予測を書き戻す(動的剛体一覧, id_a, 解いた後.予測a);
        予測を書き戻す(動的剛体一覧, id_b, 解いた後.予測b);
        Ok(())
    }

    fn 接触点集合を解く(
        &self,
        集合: &mut [剛体と剛体の接触拘束],
        射影の前: 接触の二つの参加者,
        台帳の剛体: (&剛体, &剛体),
        接触物性: crate::contact::contact_property::接触物性,
        滑走中か: bool,
    ) -> 接触の二つの参加者 {
        if 滑走中か {
            return 法線だけを同時に解く(集合, 射影の前, 台帳の剛体);
        }
        let (参加者a, 参加者b) = 射影の前.姿勢自由度の参加者を組む(台帳の剛体.0, 台帳の剛体.1);
        let (連立方程式, 点を入れた結果) = 法線と接線の連立方程式を組む(&self.計器, 集合, &参加者a, &参加者b);
        let (結末, 解いた回数) = 連立方程式.相補条件を満たす有効集合で同時に解いて解いた回数も返す();
        self.計器.粘着の候補の求解を数える(&結末, 解いた回数);
        let 相補条件を満たす有効集合を探した結末::有効集合が定まった { 同時解, 受理の材料 } = 結末 else {
            return 法線だけを同時に解く(集合, 射影の前, 台帳の剛体);
        };
        let 仮の乗数 = 仮の乗数の集まりを求める(集合, &連立方程式, &同時解, &点を入れた結果);
        let 受理 = 受理の材料.円錐の判定を記して判定する(仮の乗数.円錐の内側か(接触物性));
        self.計器.受理の判定を数える(&受理, &連立方程式);
        match 受理 {
            混合連立方程式の受理の結果::受理した => {}
            混合連立方程式の受理の結果::円錐を超えた => {
                return 粘着の候補を捨てて滑走中にする(集合, 射影の前, 台帳の剛体, &仮の乗数);
            }
            混合連立方程式の受理の結果::数値の契約を破った(_) => {
                return 法線だけを同時に解く(集合, 射影の前, 台帳の剛体);
            }
        }
        for (添字, 拘束) in 集合.iter_mut().enumerate() {
            拘束.法線と接線の連立方程式の法線の乗数の増分を取り込む(&参加者a, &参加者b, 同時解.一点の法線の乗数の増分(添字));
            拘束.静止摩擦の仮の乗数を確定する(仮の乗数.一点の仮の接線の乗数(添字).確定する接線の乗数());
        }
        射影の前.二つの補正を適用する(
            &連立方程式.第1の参加者への補正の合計(&同時解),
            &連立方程式.第2の参加者への補正の合計(&同時解),
        )
    }
}

// 円錐を超えた粘着の候補を全部捨て、同じ開始の配置から法線だけの連立方程式を解いて集合を滑走中へ移す。
// 錨を置き直す先は、法線だけの連立方程式を解き終えた2つの配置で重なっている点である。
fn 粘着の候補を捨てて滑走中にする(
    集合: &mut [剛体と剛体の接触拘束],
    射影の前: 接触の二つの参加者,
    台帳の剛体: (&剛体, &剛体),
    仮の乗数: &接触点集合の仮の乗数の集まり,
) -> 接触の二つの参加者 {
    let 法線を解いた後 = 法線だけを同時に解く(集合, 射影の前, 台帳の剛体);
    let (解いた後のa, 解いた後のb) = 法線を解いた後.姿勢自由度の参加者を組む(台帳の剛体.0, 台帳の剛体.1);
    for (添字, 拘束) in 集合.iter_mut().enumerate() {
        拘束.接触点集合が滑走中になったと印す(&解いた後のa, &解いた後のb);
        if 仮の乗数.一点の仮の接線の乗数(添字).集合が円錐を超えても解放するか() {
            拘束.静止摩擦の接線の乗数を零へ解放する();
        }
    }
    法線を解いた後
}
