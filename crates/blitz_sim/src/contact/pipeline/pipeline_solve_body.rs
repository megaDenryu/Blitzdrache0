//! 剛体どうしの接触点集合の位置反復(判断12・13)。
//! 接触点集合1つの法線の行と接線の行を1回の混合連立方程式として同時に解き、混合連立方程式の受理の判定(数値の契約4つと円錐)を
//! 通った解だけを2つの剛体の配置と法線の乗数と接線の乗数へ一括で確定する。円錐を超えたときは同じ開始の配置から法線
//! だけの連立方程式を解き直して集合を滑走中へ移し、解けなかったときと数値の契約を破ったとき(退避の枝)は法線だけの連立方程式を
//! 解き直すだけで滑走中にはしない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12」「判断13」。

mod participant_lookup;

use participant_lookup::{予測を探す, 予測を書き戻す, 台帳から引く};

use super::pipeline_body_rows::{接触の二つの参加者, 法線だけを同時に解く, 法線と接線の連立方程式を組む};
