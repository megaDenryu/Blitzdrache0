//! 剛体どうしの接触点集合の位置反復(判断12・13)。
//! 接触点集合1つの法線の行と接線の行を1回の混合連立として同時に解き、更新後の乗数でクーロン円錐を1度だけ判定し、
//! 内側なら2つの剛体の配置と法線の乗数と接線の乗数を一括で確定する。超えたときと解けなかったときは、同じ開始の配置から
//! 法線だけの連立を解き直し、その法線の解だけを確定して集合を滑走中へ移す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12」「判断13」。

use super::pipeline_body_rows::{接触の二つの参加者, 法線だけを同時に解く, 法線と接線の連立を組む};
use super::pipeline_error::接触の工程エラー;
use super::pipeline_solver::接触の解法ソルバー;
use super::substep_predict::細分の動的剛体;
use super::tentative_multipliers::仮の乗数の集まりを求める;
use crate::contact::body_body_contact::剛体と剛体の接触拘束;
use crate::contact::normal_tangential_system::相補条件を満たす有効集合を探した結末;
use crate::rigid_body::{剛体, 剛体の識別子, 剛体エラー};

impl 接触の解法ソルバー {
    pub(super) fn 剛体どうしの接触点集合を一回反復する(
        &self,
        集合: &mut [剛体と剛体の接触拘束],
        動的剛体一覧: &mut [細分の動的剛体],
        剛体一覧: &[剛体],
    ) -> Result<(), 接触の工程エラー> {
        let Some(先頭) = 集合.first() else {
            return Ok(());
        };
        let (id_a, id_b) = (先頭.履歴の鍵().小さい方の剛体(), 先頭.履歴の鍵().大きい方の剛体());
        let (接触物性, 滑走中か) = (先頭.引数().接触物性, 先頭.静止摩擦の解の状態().滑走中か());
        let 台帳の剛体 = (台帳から引く(剛体一覧, id_a)?, 台帳から引く(剛体一覧, id_b)?);
        let 射影の前 = 接触の二つの参加者 {
            予測a: 予測を探す(動的剛体一覧, id_a),
            予測b: 予測を探す(動的剛体一覧, id_b),
        };
        let 解いた後 = self.接触点集合を解く(集合, 射影の前, 台帳の剛体, 接触物性, 滑走中か);
        予測を書き戻す(動的剛体一覧, id_a, 解いた後.予測a);
        予測を書き戻す(動的剛体一覧, id_b, 解いた後.予測b);
        Ok(())
    }

    fn 接触点集合を解く(
        &self,
        集合: &mut [剛体と剛体の接触拘束],
        射影の前: 接触の二つの参加者,
        台帳の剛体: (&剛体, &剛体),
        接触物性: crate::contact::contact_property::接触物性,
        滑走中か: bool,
    ) -> 接触の二つの参加者 {
        if 滑走中か {
            return 法線だけを同時に解く(集合, 射影の前, 台帳の剛体);
        }
        let (参加者a, 参加者b) = 射影の前.姿勢自由度の参加者を組む(台帳の剛体.0, 台帳の剛体.1);
        let (連立, 点を入れた結果) = 法線と接線の連立を組む(集合, &参加者a, &参加者b);
        let (結末, 解いた回数) = 連立.相補条件を満たす有効集合で同時に解いて解いた回数も返す();
        self.解いた回数を累計へ足す(解いた回数);
        let 相補条件を満たす有効集合を探した結末::有効集合が定まった(同時解) = 結末 else {
            return 法線だけを同時に解く(集合, 射影の前, 台帳の剛体);
        };
        let 仮の乗数 = 仮の乗数の集まりを求める(集合, &連立, &同時解, &点を入れた結果);
        if !仮の乗数.円錐の内側か(接触物性) {
            let 法線を解いた後 = 法線だけを同時に解く(集合, 射影の前, 台帳の剛体);
            let (解いた後のa, 解いた後のb) = 法線を解いた後.姿勢自由度の参加者を組む(台帳の剛体.0, 台帳の剛体.1);
            for (添字, 拘束) in 集合.iter_mut().enumerate() {
                拘束.接触点集合が滑走中になったと印す(&解いた後のa, &解いた後のb);
                if 仮の乗数.一点の仮の接線の乗数(添字).集合が円錐を超えても解放するか() {
                    拘束.静止摩擦の接線の乗数を零へ解放する();
                }
            }
            return 法線を解いた後;
        }
        for (添字, 拘束) in 集合.iter_mut().enumerate() {
            拘束.法線と接線の連立の法線の乗数の増分を取り込む(&参加者a, &参加者b, 同時解.一点の法線の乗数の増分(添字));
            拘束.静止摩擦の仮の乗数を確定する(仮の乗数.一点の仮の接線の乗数(添字).確定する接線の乗数());
        }
        射影の前.二つの補正を適用する(&連立.第1の参加者への補正の合計(&同時解), &連立.第2の参加者への補正の合計(&同時解))
    }
}

fn 台帳から引く(剛体一覧: &[剛体], 識別子: 剛体の識別子) -> Result<&剛体, 接触の工程エラー> {
    Ok(剛体一覧.get(識別子.配列添字()).ok_or(剛体エラー::剛体が登録されていない { 識別子 })?)
}

// 起きている動的剛体だけがこの細分の予測を持つ。
fn 予測を探す(動的剛体一覧: &[細分の動的剛体], 識別子: 剛体の識別子) -> Option<crate::rigid_xpbd::予測の状態> {
    動的剛体一覧.iter().find(|剛体| 剛体.識別子 == 識別子).map(|剛体| 剛体.予測)
}

fn 予測を書き戻す(
    動的剛体一覧: &mut [細分の動的剛体], 識別子: 剛体の識別子, 予測: Option<crate::rigid_xpbd::予測の状態>
) {
    let (Some(予測), Some(対象)) = (予測, 動的剛体一覧.iter_mut().find(|剛体| 剛体.識別子 == 識別子)) else {
        return;
    };
    対象.予測 = 予測;
}
