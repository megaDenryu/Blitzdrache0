//! 箱の塔の休止と再開の検査(判断18)。塔が立つことの検査は `tower_standing_tests.rs` が持つ。
//! 場面の組み立ては `tower_fixture.rs` へ切り出している。
//! 1本目は2026-09-05の時点で落ちている。原因は休止の工程でなく、上下に積んだ同じ大きさの箱どうしの接触点集合の
//! 特徴の識別が細分ごとに入れ替わることであり、Issue #75 が所有する。相対配置が1.4e-7メートルしか動かない細分でも
//! 特徴が入れ替わり、静止摩擦の錨が置き直されて判断18の静穏の4条件目が成立しない。実測は
//! `_doc/計測/剛体の接触の休止の切り分け_2026-09-05.md` にある。休止の機構そのものが働くことは
//! `side_by_side_rest_tests.rs` が固定している。閾値は緩めず、この検査は落ちたまま残す。
//! 錨の条件だけを無視すると、残り3条件は最大64細分連続で成立する。休止の判定は2026-09-05のオーナーの裁定で細分ごとへ移り、
//! 閾値は連続した静穏の物理時間0.125秒(細分数16では120細分)になった。錨の条件を外した反実仮想ではこの粒度で123刻みで休止する。

use blitz_math::{ニュートン秒, メートル, ワールド, 位置, 衝撃};

use super::tower_fixture::箱の塔の場面を作る;
use crate::rigid_body::{休止から起きた理由, 姿勢, 配置};

#[test]
fn 箱十段の塔が六百刻み以内に休止し衝撃で全体が起きる() {
    let (mut 工程, mut 台帳, 箱id一覧, _) = 箱の塔の場面を作る(10, false);
    let mut 休止した = false;
    for 刻み in 0..600 {
        if let Err(誤り) = 工程.一刻み進める(&mut 台帳) {
            panic!("刻み {刻み} で一刻み進めるエラー: {誤り:?}");
        }
        休止した = 箱id一覧
            .iter()
            .all(|&id| 台帳.参照する(id).is_ok_and(|剛体| 剛体.実行状態().休止しているか()));
        if 休止した {
            break;
        }
    }
    assert!(休止した, "600刻み以内に箱10段の塔が休止しなかった");

    let p = 衝撃::成分から生成する(ニュートン秒::生成する(0.0), ニュートン秒::生成する(5.0), ニュートン秒::生成する(0.0));
    let Ok(()) = 台帳.重心へ衝撃を加える(箱id一覧[0], p) else {
        panic!();
    };
    let Ok(()) = 工程.一刻み進める(&mut 台帳) else {
        panic!();
    };
    for &id in &箱id一覧 {
        let Ok(剛体) = 台帳.参照する(id) else {
            panic!();
        };
        assert!(剛体.実行状態().起きているか(), "衝撃後に起きていない剛体がある: {id:?}");
        assert_eq!(
            剛体.実行状態().直近に休止から起きた理由(),
            Some(休止から起きた理由::作用の投入),
            "衝撃で起きた剛体が作用の投入以外の理由を記録している: {id:?}"
        );
    }
}

#[test]
fn 運動学的な床が動き出すと上の箱が起きる() {
    let (mut 工程, mut 台帳, 箱id一覧, 床id) = 箱の塔の場面を作る(1, true);
    let 箱id = 箱id一覧[0];
    let mut 休止した = false;
    for _ in 0..600 {
        let Ok(()) = 工程.一刻み進める(&mut 台帳) else {
            panic!();
        };
        let Ok(箱) = 台帳.参照する(箱id) else {
            panic!();
        };
        if 箱.実行状態().休止しているか() {
            休止した = true;
            break;
        }
    }
    assert!(休止した, "運動学的な床の上の箱が600刻み以内に休止しなかった");

    let 新配置 = 配置::生成する(
        位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(-0.4), メートル::生成する(0.0)),
        姿勢::恒等(),
    );
    台帳.遷移の予約().運動学的にする(床id, 新配置);
    let Ok(()) = 工程.一刻み進める(&mut 台帳) else {
        panic!();
    };
    let Ok(箱) = 台帳.参照する(箱id) else {
        panic!();
    };
    assert!(箱.実行状態().起きているか(), "床の移動後に箱が起きなかった");
    assert_eq!(
        箱.実行状態().直近に休止から起きた理由(),
        Some(休止から起きた理由::新しい接触),
        "運動学的な床の移動で起きた箱が新しい接触以外の理由を記録している"
    );
}
