//! Issue #103の段階A2の計測3のうち、箱10段の塔(細分16・本番の適用規則)の側の計器。剛体どうしの接触の混合連立に
//! ついて、固有の向きが偽の固有値の下限のどれだけ上に居るかと、その向きを捨てずに解いたときの増分 |β_k| ÷ λ_k の
//! 最大を刻みごとに綴る。候補(α)は下限のすぐ上の向きも解くため、そこに向きが居れば増分が桁で膨れる。
//! 坂の側は `crates/blitz_sim/src/contact/scene/numeric_contract_record/tolerance_dependence/eigen_direction_switch/eigen_floor_band.rs` が別に綴る。
//! 塔の場面と刻みの進め方は`tower_row_admission_record`と同じ`箱の塔の場面を作る(10, false)`である。合否は判定しない。
//! 実行は `cargo test -p blitz_sim --release 偽の固有値の下限の帯_塔 -- --ignored --nocapture` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::tower_fixture::箱の塔の場面を作る;
use crate::contact::normal_tangential_system::偽の固有値の下限に対する固有の向きの分布;

const 綴る刻みの数: usize = 4;
const 塔の段数: u16 = 10;
const 一刻みに綴る求解の上限: usize = 6;

// 1刻みぶんの分布を綴り、帯に向きが居た求解の数と、増分の最大2つを返す。
fn 一刻みの分布を綴る(刻み: usize, 分布一覧: &[偽の固有値の下限に対する固有の向きの分布]) -> (usize, f32, f32) {
    let 帯に居た求解 = 分布一覧.iter().filter(|分布| 分布.下限のすぐ上に居る向きの本数() > 0).count();
    let 帯の増分の最大 = 分布一覧
        .iter()
        .map(偽の固有値の下限に対する固有の向きの分布::下限のすぐ上に居る向きの増分の最大)
        .fold(0.0, f32::max);
    let 真の向きの増分の最大 = 分布一覧
        .iter()
        .map(偽の固有値の下限に対する固有の向きの分布::真の向きの増分の最大)
        .fold(0.0, f32::max);
    println!(
        "  H 刻み{刻み} 求解={}件 帯に向きが居た求解={帯に居た求解}件 帯の増分の最大={帯の増分の最大:.4e} 真の向きの増分の最大={真の向きの増分の最大:.4e}",
        分布一覧.len()
    );
    for 分布 in 分布一覧.iter().take(一刻みに綴る求解の上限) {
        println!("    H {}", 分布.綴り());
    }
    (帯に居た求解, 帯の増分の最大, 真の向きの増分の最大)
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 偽の固有値の下限の帯_塔の刻みごとの分布を綴る() {
    let (mut 工程, mut 台帳, _, _) = 箱の塔の場面を作る(塔の段数, false);
    工程.解法.計器.固有の向きの分布を数え始めて溜まった分を読む();
    println!("[箱{塔の段数}段の塔_本番の適用規則] 偽の固有値の下限に対する固有の向きの分布");
    let (mut 帯の延べ数, mut 帯の増分の最大, mut 真の向きの増分の最大) = (0, 0.0f32, 0.0f32);
    for 刻み in 0..綴る刻みの数 {
        let Ok(_) = 工程.一刻み進めて細分ごとのバッチを返す(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        let 分布一覧 = 工程.解法.計器.固有の向きの分布を数え始めて溜まった分を読む();
        let (帯, 帯の最大, 真の最大) = 一刻みの分布を綴る(刻み, &分布一覧);
        帯の延べ数 += 帯;
        帯の増分の最大 = 帯の増分の最大.max(帯の最大);
        真の向きの増分の最大 = 真の向きの増分の最大.max(真の最大);
    }
    println!(
        "  要約 [箱{塔の段数}段の塔] 帯に向きが居た求解の延べ数={帯の延べ数}件 帯の増分の最大={帯の増分の最大:.4e} 真の向きの増分の最大={真の向きの増分の最大:.4e}"
    );
}
