//! 坂の上の2段の箱の一次計測が使う2つの集計(親の2026-09-12の指示)。1つは接触の対1つぶんの乗数の集計であり、
//! もう1つは静止の解が要求する乗数の解析の値である。綴る工程(`stacked_slope_cone_record`)から分けているのは、
//! こちらが接触点を足して比を出す計算であり、あちらが場面を走らせて表を並べる工程だからである。
//! 注意: 接線は点ごとの大きさの合計であり、解法の円錐の判定が読む合力(向きを持つ和)の大きさではない。点ごとの向きが
//! 打ち消し合う分だけ、この合計は合力の大きさ以上になる。したがって大きさの比は円錐の比の上界であり、比が静止摩擦係数
//! を超えていることは円錐を超えたことを意味しない。円錐を超えた印は滑走中と印された点の数である。
//! 静止の解が要求する乗数は、重力 g・傾き θ・箱の質量 m・細分の刻み幅 h から、法線 m g cosθ h²、接線 m g sinθ h² と
//! して導く。判断14が法線反力を f_n = λ_n ÷ h² と置くため、力へ h² を掛けた量が乗数である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13」「判断14」

#![cfg(test)]

use crate::contact::body_body_contact::剛体と剛体の接触拘束;

// `contact_test_pipeline_scene` が置く重力の大きさと、細分数16のときの細分の刻み幅の秒である。
const 重力の大きさ: f32 = 9.8;
const 細分の刻み幅の秒: f32 = 1.0 / 960.0;
const 箱の質量: f32 = 1.0;

/// 接触の対1つぶんの、細分の終わりの乗数の集計。
#[derive(Debug, Clone, Copy, Default)]
pub(super) struct 接触の対の乗数の集計 {
    法線の乗数の合計: f32,
    接線の乗数の大きさの合計: f32,
    接触点の数: usize,
    滑走中の点の数: usize,
}

impl 接触の対の乗数の集計 {
    /// 対を見分ける鍵。2つの剛体の台帳の添字の組であり、床が0・下の箱が1・上の箱が2である。
    pub(super) fn 対の鍵(拘束: &剛体と剛体の接触拘束) -> (usize, usize) {
        (拘束.引数().剛体a.配列添字(), 拘束.引数().剛体b.配列添字())
    }

    pub(super) fn 一点を足す(&mut self, 拘束: &剛体と剛体の接触拘束) {
        self.法線の乗数の合計 += 拘束.法線のラグランジュ乗数().値();
        self.接線の乗数の大きさの合計 += 拘束.静止摩擦の解の状態().接線のラグランジュ乗数().大きさ().値();
        self.接触点の数 += 1;
        if 拘束.静止摩擦の解の状態().滑走中か() {
            self.滑走中の点の数 += 1;
        }
    }

    pub(super) fn 綴り(&self) -> String {
        let 比 = if self.法線の乗数の合計 == 0.0 {
            f32::NAN
        } else {
            self.接線の乗数の大きさの合計 / self.法線の乗数の合計
        };
        format!(
            "法線の合計={:.4e} 接線の大きさの合計={:.4e} 大きさの比={比:.4} 点={} 滑走中={}",
            self.法線の乗数の合計, self.接線の乗数の大きさの合計, self.接触点の数, self.滑走中の点の数
        )
    }
}

/// 2段の箱が静止しているときに各対が担うべき乗数の解析の値。
#[derive(Debug, Clone, Copy)]
pub(super) struct 静止の解が要求する乗数 {
    上の対の法線: f32,
    上の対の接線: f32,
    下の対の法線: f32,
    下の対の接線: f32,
}

impl 静止の解が要求する乗数 {
    pub(super) fn 傾きの正接と箱の質量から導く(傾きの正接: f32) -> Self {
        let 余弦 = 1.0 / (1.0 + 傾きの正接 * 傾きの正接).sqrt();
        let 一つの箱の重さへ掛ける量 = 箱の質量 * 重力の大きさ * 細分の刻み幅の秒 * 細分の刻み幅の秒;
        let (上の対の法線, 上の対の接線) = (一つの箱の重さへ掛ける量 * 余弦, 一つの箱の重さへ掛ける量 * 傾きの正接 * 余弦);
        Self {
            上の対の法線,
            上の対の接線,
            下の対の法線: 2.0 * 上の対の法線,
            下の対の接線: 2.0 * 上の対の接線,
        }
    }

    pub(super) fn 綴り(&self) -> String {
        format!(
            "[静止の解が要求する乗数] 下の箱と上の箱の対: 法線={:.4e} 接線={:.4e} 比={:.4} / 床と下の箱の対: 法線={:.4e} 接線={:.4e} 比={:.4}",
            self.上の対の法線,
            self.上の対の接線,
            self.上の対の接線 / self.上の対の法線,
            self.下の対の法線,
            self.下の対の接線,
            self.下の対の接線 / self.下の対の法線
        )
    }
}
