//! 判断13の反証(4)(e)の計測)。合否は判定しない(判定は `stacked_slope_tests` が持つ)。
//! 綴るのは、2つの箱の坂に沿った変位・最後の刻みの滑走中の接触点の有無・粘着の候補が解けなかった延べ数・受理の破れの内訳・
//! 解いた連立の回数である。場面は `stacked_slope_fixture` が組む。
//! 実行は `cargo test -p blitz_sim --release 本実装の検収_坂の上の二段の箱 -- --ignored --nocapture` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::stacked_slope_fixture::坂の上の二段の箱の場面;
use super::stacked_slope_spec::原点;
use crate::contact::friction_coefficient::摩擦係数;
use crate::contact::normal_tangential_system::{
    接線の行への許容差の当て方, 解けたと見なす許容差の倍率, 試験の許容差の当て方
};
use crate::rigid_body::剛体の識別子;

const 綴る刻みの数: usize = 600;
const 傾きの正接: f32 = 0.55;
const 振る受理の倍率: &[f32] = &[0.5, 1.0, 2.0];

fn 重心の下り向きの成分(場面: &坂の上の二段の箱の場面, 箱: 剛体の識別子) -> f32 {
    let Ok(剛体) = 場面.台帳.参照する(箱) else {
        panic!("箱が台帳に無い");
    };
    (剛体.配置().重心の位置() - 原点()).方向に沿う長さ(場面.幾何.下り向き()).値()
}

fn 一つの当て方を綴る(見出し: &str, 当て方: 試験の許容差の当て方) {
    let Ok(摩擦) = 摩擦係数::生成する(0.6) else {
        panic!("摩擦係数を作れない");
    };
    let mut 場面 = 坂の上の二段の箱の場面::生成する(傾きの正接, 摩擦);
    場面.工程.解法.計器.許容差の当て方を差し替える(当て方);
    let (初めの下, 初めの上) = (重心の下り向きの成分(&場面, 場面.下の箱), 重心の下り向きの成分(&場面, 場面.上の箱));
    let mut 最後の刻みに滑走中の点があった = false;
    for 刻み in 0..綴る刻みの数 {
        let Ok(細分ごと) = 場面.工程.一刻み進めて細分ごとのバッチを返す(&mut 場面.台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        最後の刻みに滑走中の点があった = 細分ごと
            .last()
            .is_some_and(|バッチ| バッチ.剛体どうしの接触拘束().iter().any(|拘束| 拘束.静止摩擦の解の状態().滑走中か()));
    }
    println!(
        "[{見出し}] 下の箱の変位={:.3e} 上の箱の変位={:.3e} 最後の刻みに滑走中の点={} 解けず{}(精度不足{} {}) 解いた回数={}",
        重心の下り向きの成分(&場面, 場面.下の箱) - 初めの下,
        重心の下り向きの成分(&場面, 場面.上の箱) - 初めの上,
        最後の刻みに滑走中の点があった,
        場面.工程.解法.計器.粘着の候補が解けなかった延べ数(),
        場面.工程.解法.計器.表現の精度が不足した延べ数(),
        場面.工程.解法.計器.受理の破れ().綴り(),
        場面.工程.解法.計器.解いた回数の累計を読んで零に戻す().階層の走査が解いた数()
    );
}

