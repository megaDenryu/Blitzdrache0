//! 接触の品質と時間方針(判断5・11・12・14)。
//! 起動時に決まって二度と変わらない時間刻みと品質設定を保持する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断5」「判断11」「判断12」「判断14」。

use crate::contact::batch_builder::接触拘束のバッチの組み立て;
use crate::contact::mixing_rule::混合則;
use crate::contact::solver_quality::接触を解く品質の設定;
use crate::rigid_xpbd::細分数;
use crate::xpbd::{コンプライアンス, 刻み幅};

/// 起動時に決まり刻みを跨いで不変の時間刻みとソルバー品質の設定群。
#[derive(Debug, Clone, PartialEq)]
pub struct 接触の品質と時間方針 {
    基本刻み幅: 刻み幅,
    細分数: 細分数,
    細分の刻み幅: 刻み幅,
    解く品質: 接触を解く品質の設定,
    混合則: 混合則,
}

impl 接触の品質と時間方針 {
    pub fn 生成する(
        基本刻み幅: 刻み幅, 細分数: 細分数, 細分の刻み幅: 刻み幅, 解く品質: 接触を解く品質の設定, 混合則: 混合則
    ) -> Self {
        Self {
            基本刻み幅,
            細分数,
            細分の刻み幅,
            解く品質,
            混合則,
        }
    }

    pub fn 基本刻み幅(&self) -> 刻み幅 {
        self.基本刻み幅
    }

    pub fn 細分数(&self) -> 細分数 {
        self.細分数
    }

    pub fn 細分の刻み幅(&self) -> 刻み幅 {
        self.細分の刻み幅
    }

    pub fn 解く品質(&self) -> &接触を解く品質の設定 {
        &self.解く品質
    }

    pub fn 混合則(&self) -> &混合則 {
        &self.混合則
    }

    pub fn バッチ組み立て器を作る(&self, 候補対数: usize) -> 接触拘束のバッチの組み立て<'_> {
        接触拘束のバッチの組み立て::生成する(&self.混合則, コンプライアンス::硬い(), self.細分の刻み幅, 候補対数.max(1))
    }
}
