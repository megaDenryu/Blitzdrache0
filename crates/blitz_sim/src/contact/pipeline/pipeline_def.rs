//! 剛体の接触の一刻みの工程の定義(判断19)。
//! 時間方針・空間と世界・接触履歴・解法ソルバーの4つの自律型を統括する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」。

use blitz_collision::shape::{任意姿勢の直方体, 直方体の軸ごとの半分の長さ};

use super::pipeline_error::接触の工程エラー;
use super::pipeline_history::接触履歴の保持;
use super::pipeline_policy::接触の品質と時間方針;
use super::pipeline_solver::接触の解法ソルバー;
use super::pipeline_space::接触の空間と世界;
use crate::contact::material_id::材質の識別子;
use crate::contact::static_world_partner::静的世界の接触相手;
use crate::rigid_body::{剛体の識別子, 配置};

pub struct 剛体の接触の一刻みの工程 {
    pub(super) 時間方針: 接触の品質と時間方針,
    pub(super) 空間: 接触の空間と世界,
    pub(super) 履歴: 接触履歴の保持,
    pub(super) 解法: 接触の解法ソルバー,
}

impl 剛体の接触の一刻みの工程 {
    /// 4つの自律型を受け取って組む。それぞれを別々に作るのは、寿命と生成の条件が違うためである(起動時に決まる時間方針、
    /// 剛体の登録で育つ空間と世界、刻みを跨いで持ち越す履歴、解くための道具である解法)。
    pub fn 生成する(
        時間方針: 接触の品質と時間方針, 空間: 接触の空間と世界, 履歴: 接触履歴の保持, 解法: 接触の解法ソルバー
    ) -> Self {
        Self {
            時間方針, 空間, 履歴, 解法
        }
    }

    pub fn 剛体を登録する(
        &mut self,
        識別子: 剛体の識別子,
        初期配置: &配置,
        半分の長さ: 直方体の軸ごとの半分の長さ,
        材質: 材質の識別子,
    ) -> Result<(), 接触の工程エラー> {
        self.空間.剛体を登録する(識別子, 初期配置, 半分の長さ, 材質)?;
        self.履歴.初期配置を記録する(識別子, 初期配置);
        Ok(())
    }

    pub fn 静的世界の接触相手を登録する(&mut self, 相手: 静的世界の接触相手, 直方体: 任意姿勢の直方体) {
        self.空間.静的世界の接触相手を登録する(相手, 直方体);
    }

    pub fn 前の配置(&self, 識別子: 剛体の識別子) -> Option<&配置> {
        self.履歴.前の配置(識別子)
    }
}
