//! 受理の判定が(B1)を破った1件について、その連立から読む量(判断13。試験と計器の専用。親の2026-09-12の指示による診断)。
//! 読むのは、残差と許容差の比・破れた行の C_t と閾値 δ(行が積まれた理由。C_t/δ が大きいほど本物の荷重の行である)・勝った
//! 有効集合・擬似逆が捨てた向きの数(偽の固有値と右辺が許容差の内側)である。比が大きい群は解そのものの失敗の疑いがある
//! ため、比 10 を境に2群へ分けて数える。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use crate::contact::normal_tangential_system::{
    単精度の解の内訳, 受理の契約を破った理由, 接触点集合の法線と接線の連立, 混合連立の受理の結果
};
use crate::contact::symmetric_system::擬似逆が固有の向きを捨てた理由;

/// 比の群の境。これ以上の比は解そのものの失敗の疑いがある。
pub(super) const 比の群の境: f32 = 10.0;

/// (B1)の破れ1件の読み取り。
#[derive(Debug, Clone, PartialEq)]
pub(super) struct 受理の破れの読み取り {
    pub(super) 比: f32,
    pub(super) 残差の綴り: String,
    pub(super) 行の接線変位と閾値: Option<(f32, f32)>, // 破れた行の C_t と δ。行が無ければ無し
    pub(super) 有効集合の綴り: String,
    pub(super) 偽の固有値の数: usize,
    pub(super) 内側で捨てた数: usize,
}

impl 受理の破れの読み取り {
    /// 受理の結末が(B1)の破れなら読み取りを作り、それ以外なら無し。連立の内訳は勝った有効集合で読み直す。
    pub(super) fn 結末と連立から読む(
        結果: &混合連立の受理の結果, 連立: &接触点集合の法線と接線の連立
    ) -> Option<Self> {
        let 混合連立の受理の結果::数値の契約を破った(理由) = 結果 else {
            return None;
        };
        let 受理の契約を破った理由::積んだ接線の行の残差が許容差を超えた { 点の番号, 残差 } = 理由 else {
            return None;
        };
        let 内訳: Option<単精度の解の内訳> = 連立.定まった解の内訳を読む();
        Some(Self {
            比: 残差.許容差に対する比(),
            残差の綴り: 残差.綴り(),
            行の接線変位と閾値: 連立
                .接線の一行を読む(*点の番号)
                .map(|一行| (一行.接線変位の長さ().値(), 一行.勾配().解けたと見なす許容差().値())),
            有効集合の綴り: 内訳.as_ref().map_or_else(|| "定まらず".to_owned(), 単精度の解の内訳::有効集合の綴り),
            偽の固有値の数: 内訳
                .as_ref()
                .map_or(0, |内訳| 内訳.捨てた向きの数(擬似逆が固有の向きを捨てた理由::偽の固有値)),
            内側で捨てた数: 内訳
                .as_ref()
                .map_or(0, |内訳| 内訳.捨てた向きの数(擬似逆が固有の向きを捨てた理由::右辺が許容差の内側)),
        })
    }

    pub(super) fn 比が大きい群か(&self) -> bool {
        self.比 >= 比の群の境
    }

    pub(super) fn 綴り(&self) -> String {
        let 行 = self.行の接線変位と閾値.map_or_else(
            || "行なし".to_owned(),
            |(接線変位, 閾値)| format!("C_t={接線変位:.3e}/δ={閾値:.3e}(比{:.1})", 接線変位 / 閾値),
        );
        format!(
            "残差{} {行} 有効集合={} 偽の固有値{} 内側で捨てた{}",
            self.残差の綴り, self.有効集合の綴り, self.偽の固有値の数, self.内側で捨てた数
        )
    }
}
