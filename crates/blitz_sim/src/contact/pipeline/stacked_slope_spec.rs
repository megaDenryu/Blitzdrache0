//! 坂の上の2段の箱の場面の幾何の指定(判断13の2026-09-12の実装の細目の反証(4)(e))。傾きの正接から、床と箱が
//! 共有する姿勢・床の面の法線・坂の下り向き・床の上面から法線の向きへ測った箱の重心の位置を導く。
//! 剛体を台帳と工程へ置く工程(`stacked_slope_fixture`)から分けているのは、こちらが場面の状態を持たない三角関数だけの
//! 計算であり、試験が下り向きの変位を測るのにも使うためである(`scene/slope_geometry` と同じ分け方)。
//! 幾何: 傾き θ で x軸まわりに回した姿勢 q = (sin(θ/2), 0, 0, cos(θ/2))、面の法線 n = R(q) ŷ = (0, cosθ, sinθ)、
//! 下り向き d = (0, −sinθ, cosθ)。床の上面は n·x = 床の半分の厚み の面である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use blitz_math::{メートル, ワールド, 二段の位置, 位置, 変位, 方向};

use crate::rigid_body::姿勢;

pub(super) const 床の半分の厚み: f32 = 0.5;
pub(super) const 箱の半分の長さ: f32 = 0.5;
const 初めの食い込み: f32 = 1.0e-4;

/// 坂の上の2段の箱の場面の幾何。傾きの正接だけで決まる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 坂の上の二段の箱の幾何 {
    傾きの正接: f32,
}

impl 坂の上の二段の箱の幾何 {
    pub(super) fn 傾きの正接から生成する(傾きの正接: f32) -> Self {
        Self { 傾きの正接 }
    }

    // 床と箱が共有する、x軸まわりに傾けた姿勢。
    pub(super) fn 姿勢(&self) -> 姿勢 {
        let 半角 = self.傾きの正接.atan() / 2.0;
        let Ok(姿勢) = 姿勢::生成する(半角.sin(), 0.0, 0.0, 半角.cos()) else {
            panic!("傾きの姿勢を作れない");
        };
        姿勢
    }

    // 床の面の法線。箱を面へ密着させる位置もこの向きで測る。
    pub(super) fn 面の法線(&self) -> 方向<ワールド> {
        let (正弦, 余弦) = self.傾きの正弦と余弦();
        let Ok(法線) = 方向::生成する(0.0, 余弦, 正弦) else {
            panic!("面の法線を作れない");
        };
        法線
    }

    // 坂の面を最も急に下る向き。重力の面内成分の向きである。
    pub(super) fn 下り向き(&self) -> 方向<ワールド> {
        let (正弦, 余弦) = self.傾きの正弦と余弦();
        let Ok(下り向き) = 方向::生成する(0.0, -正弦, 余弦) else {
            panic!("下り向きを作れない");
        };
        下り向き
    }

    // 床の中心(原点)から法線の向きへ、床の上面と指定の段の箱の重心までの長さ。段は0が床に乗る箱である。
    // 箱は1段ごとに初めの食い込みのぶんだけ沈めて置く。
    pub(super) fn 箱の重心(&self, 段: u8) -> 二段の位置<ワールド> {
        let 段の数 = f32::from(段) + 1.0;
        let 長さ = 床の半分の厚み + (2.0 * 段の数 - 1.0) * 箱の半分の長さ - 段の数 * 初めの食い込み;
        原点().変位を足す(変位::方向へ進む(self.面の法線(), メートル::生成する(長さ)))
    }

    fn 傾きの正弦と余弦(&self) -> (f32, f32) {
        let 余弦 = 1.0 / (1.0 + self.傾きの正接 * self.傾きの正接).sqrt();
        (self.傾きの正接 * 余弦, 余弦)
    }
}

/// 床の中心である世界の原点。
pub(super) fn 原点() -> 二段の位置<ワールド> {
    let 零 = メートル::生成する(0.0);
    二段の位置::位置から生成する(位置::<ワールド>::生成する(零, 零, 零))
}
