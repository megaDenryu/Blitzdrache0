//! 細分の初めに、前の細分の記録を新しい接触点集合へ配る工程(判断13・16)。
//! 継続した接触点には前の細分の錨を置き直し、始まった接触点には予測の前の配置での接触点を錨として置く。
//! 履歴の器(`pipeline_history`)と分けているのは、こちらが細分1本の初めに1度だけ走る工程であり、あちらが刻みを跨いで
//! 持ち越す状態の器だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13」「判断16」。

use super::pipeline_error::接触の工程エラー;
use super::pipeline_history::接触履歴の保持;
use super::substep_placement::細分の予測の前の配置一覧;
use crate::contact::body_body_contact::剛体と剛体の接触拘束;
use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::history::接触の対応付け;

impl 接触履歴の保持 {
    /// 前の細分の錨を継続した接触点へ配り、この細分で始まった接触点の錨を予測の前の配置へ置く(判断13・16)。
    /// 開始の枝を放っておくと、その細分の錨からの接線変位が零になって位置の静止摩擦が1度も効かず、剛体は細分1本ぶんの
    /// 接線の滑りを持ったまま次の細分へ入る。次の細分は2細分ぶんの滑りを1度に戻すことになり、要る接線の乗数が跳ねて円錐を超える。
    pub(super) fn 履歴を引き継ぐ(
        &mut self,
        バッチ: &mut 接触拘束の二つのバッチ,
        予測の前の配置一覧: &細分の予測の前の配置一覧,
    ) -> Result<(), 接触の工程エラー> {
        let 持ち込み剛体: Vec<_> = バッチ
            .剛体どうしの接触拘束()
            .iter()
            .map(剛体と剛体の接触拘束::併走へ持ち込む履歴の項目)
            .collect();
        let 対応剛体: Vec<_> = self.剛体どうしの履歴.新しい細分の接触と併走する(&持ち込み剛体)?.対応付け一覧().to_vec();
        for (拘束, 対応) in バッチ.剛体どうしの接触拘束を反復のために借りる().iter_mut().zip(&対応剛体) {
            match 対応 {
                接触の対応付け::継続 { 引き継いだ記録 } => 拘束.継続の記録を引き継ぐ(*引き継いだ記録),
                接触の対応付け::開始 { .. } => {
                    let 鍵 = 拘束.履歴の鍵();
                    let (Some(aの配置), Some(bの配置)) = (
                        予測の前の配置一覧.配置を引く(鍵.小さい方の剛体()),
                        予測の前の配置一覧.配置を引く(鍵.大きい方の剛体()),
                    ) else {
                        continue;
                    };
                    拘束.開始した接触の錨を予測の前の配置へ置く(aの配置, bの配置);
                }
            }
        }
        let 持ち込み静的: Vec<_> = バッチ
            .剛体と静的世界の接触拘束()
            .iter()
            .map(剛体と静的世界の接触拘束::併走へ持ち込む履歴の項目)
            .collect();
        let 対応静的: Vec<_> = self
            .剛体と静的世界の履歴
            .新しい細分の接触と併走する(&持ち込み静的)?
            .対応付け一覧()
            .to_vec();
        for (拘束, 対応) in バッチ.剛体と静的世界の接触拘束を反復のために借りる().iter_mut().zip(&対応静的) {
            match 対応 {
                接触の対応付け::継続 { 引き継いだ記録 } => 拘束.継続の記録を引き継ぐ(*引き継いだ記録),
                接触の対応付け::開始 { .. } => {
                    let Some(配置) = 予測の前の配置一覧.配置を引く(拘束.引数().剛体) else {
                        continue;
                    };
                    拘束.開始した接触の錨を予測の前の配置へ置く(配置);
                }
            }
        }
        Ok(())
    }
}
