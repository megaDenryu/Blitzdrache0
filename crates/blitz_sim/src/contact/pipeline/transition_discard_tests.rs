//! 運動種別の遷移が接触の履歴を捨てることの検査(判断7・16)。
//! 履歴の器を直接叩くのでなく、遷移を予約して本番の工程1(構造変更の反映)を呼び、その前後で履歴の件数を比べる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断7」「判断16」。

use super::tower_fixture::箱の塔の場面を作る;
use crate::rigid_body::運動状態;

#[test]
fn 運動種別を遷移させた剛体を含む接触の履歴が工程1で捨てられる() {
    let (mut 工程, mut 台帳, 箱id一覧, _) = 箱の塔の場面を作る(3, false);
    for _ in 0..30 {
        let Ok(()) = 工程.一刻み進める(&mut 台帳) else {
            panic!("一刻み進めるのに失敗した");
        };
    }
    // 最上段を遷移させる。最下段は床との接触と第2段との接触を持ち、そのどちらも最上段を含まない。
    let 遷移させる剛体 = 箱id一覧[2];
    let 残す剛体 = 箱id一覧[0];
    assert!(
        工程.遷移した剛体の履歴の件数(遷移させる剛体) > 0,
        "遷移の前に履歴が積まれておらず、この検査は履歴が捨てられたことを見ていない"
    );

    台帳.遷移の予約().動的にする(遷移させる剛体, 運動状態::静止());
    let Ok(()) = 工程.構造変更を反映する(&mut 台帳) else {
        panic!("構造変更の反映に失敗した");
    };

    assert_eq!(
        工程.遷移した剛体の履歴の件数(遷移させる剛体),
        0,
        "遷移した剛体を含む接触の履歴が残っている"
    );
    assert!(
        工程.遷移した剛体の履歴の件数(残す剛体) > 0,
        "遷移していない剛体の接触の履歴まで捨てられている"
    );
}
