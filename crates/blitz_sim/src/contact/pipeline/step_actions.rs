//! 物理刻みの開始で剛体の蓄積器から取り出した作用(判断6・判断19の工程2)。
//! 力と回転力は一刻みの入力として細分の全部へ配り、衝撃と回転衝撃は最初の細分だけへ1度だけ渡す。
//! 後者を取り出す口を1度しか成功させないのは、2本目以降の細分へ同じ衝撃が渡ることを型で断つためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」。

use std::collections::BTreeMap;

use crate::rigid_body::{一刻みの入力, 一度だけ適用する衝撃, 剛体の識別子};

pub(super) struct 刻みの初めに取り出した作用 {
    動的な剛体の識別子一覧: Vec<剛体の識別子>,
    剛体ごとの一刻みの入力: BTreeMap<剛体の識別子, 一刻みの入力>,
    最初の細分だけへ渡す衝撃: Option<Vec<(剛体の識別子, 一度だけ適用する衝撃)>>,
}

impl 刻みの初めに取り出した作用 {
    pub(super) fn 空() -> Self {
        Self {
            動的な剛体の識別子一覧: Vec::new(),
            剛体ごとの一刻みの入力: BTreeMap::new(),
            最初の細分だけへ渡す衝撃: Some(Vec::new()),
        }
    }

    pub(super) fn 一つの剛体の作用を足す(
        &mut self, 識別子: 剛体の識別子, 入力: 一刻みの入力, 衝撃: 一度だけ適用する衝撃
    ) {
        self.動的な剛体の識別子一覧.push(識別子);
        self.剛体ごとの一刻みの入力.insert(識別子, 入力);
        if let Some(一覧) = self.最初の細分だけへ渡す衝撃.as_mut() {
            一覧.push((識別子, 衝撃));
        }
    }

    pub(super) fn 動的な剛体の識別子一覧(&self) -> &[剛体の識別子] {
        &self.動的な剛体の識別子一覧
    }

    /// この刻みで力と回転力を積分するための入力。持っていない剛体には作用が無い。
    pub(super) fn 一刻みの入力(&self, 識別子: 剛体の識別子) -> 一刻みの入力 {
        self.剛体ごとの一刻みの入力.get(&識別子).copied().unwrap_or_else(一刻みの入力::無し)
    }

    /// 衝撃と回転衝撃を取り出す。2度目からは持っていないと答えるため、2本目以降の細分へは渡らない。
    pub(super) fn 衝撃を一度だけ取り出す(&mut self) -> Option<Vec<(剛体の識別子, 一度だけ適用する衝撃)>> {
        self.最初の細分だけへ渡す衝撃.take()
    }
}
