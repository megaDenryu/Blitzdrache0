//! 細分の終わりに接線の残差を測り、その変化を打ち消す仮の補正を剛体ごとに合計する工程(判断24)。
//! 位置の反復を全部終えた後、速度の再構成の前に1度だけ走る。反復の工程(`pipeline_solve_static`・`pipeline_solve_body`)から
//! 分けているのは、あちらが反復のたびに配置を書き換える局面であるのに対し、こちらが確定した配置で1度だけ測り、
//! 配置を1ビットも書かない局面だからである。
//! **この工程が求める補正を配置へ適用してはならない。** 読むのは速度の再構成だけである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

use super::pipeline_error::接触の工程エラー;
use super::pipeline_solver::接触の解法ソルバー;
use super::substep_predict::細分の動的剛体;
use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::island::接触島;
use crate::contact::static_friction::残差の変化を打ち消す仮の補正の連立;
use crate::rigid_body::{剛体, 剛体の識別子, 剛体エラー};
use crate::rigid_xpbd::{姿勢自由度の参加者, 速度の再構成だけが読む仮の補正};

impl 接触の解法ソルバー {
    /// 島の全部の接触点集合について残差を測り、剛体ごとの仮の補正を積み上げる。
    pub(super) fn 細分の終わりの残差から仮の補正を求める(
        &self,
        バッチ: &mut 接触拘束の二つのバッチ,
        島一覧: &[接触島],
        動的剛体一覧: &mut [細分の動的剛体],
        剛体一覧: &[剛体],
    ) -> Result<(), 接触の工程エラー> {
        for 島 in 島一覧 {
            let 静的区間 = 島.剛体と静的世界の接触点集合の区間();
            for 集合番号 in 静的区間.開始()..静的区間.終了() {
                静的世界の接触点集合の残差を測る(集合番号, バッチ, 動的剛体一覧, 剛体一覧)?;
            }
            let 剛体間区間 = 島.剛体どうしの接触点集合の区間();
            for 集合番号 in 剛体間区間.開始()..剛体間区間.終了() {
                剛体どうしの接触点集合の残差を測る(集合番号, バッチ, 動的剛体一覧, 剛体一覧)?;
            }
        }
        Ok(())
    }
}

// 剛体と静的世界の接触点集合1つ。第2の参加者は動かせないため、補正は剛体の側だけへ積む。
fn 静的世界の接触点集合の残差を測る(
    集合番号: usize,
    バッチ: &mut 接触拘束の二つのバッチ,
    動的剛体一覧: &mut [細分の動的剛体],
    剛体一覧: &[剛体],
) -> Result<(), 接触の工程エラー> {
    let 集合 = バッチ.剛体と静的世界の接触点集合を反復のために借りる(集合番号);
    let Some(先頭) = 集合.first() else {
        return Ok(());
    };
    let 識別子 = 先頭.引数().剛体;
    let 参加者 = 参加者を組む(動的剛体一覧, 剛体一覧, 識別子)?;
    for 拘束 in 集合.iter_mut() {
        拘束.細分の終わりの接線の残差を測る(&参加者);
    }
    let mut 連立 = 残差の変化を打ち消す仮の補正の連立::空で始める();
    for 拘束 in 集合.iter() {
        拘束.残差の変化を仮の補正の連立へ積む(&mut 連立, &参加者);
    }
    let (補正, _) = 連立.二つの参加者への仮の補正を求める();
    仮の補正を積む(動的剛体一覧, 識別子, &補正);
    Ok(())
}

// 剛体と剛体の接触点集合1つ。2つの剛体それぞれへ補正を積む。
fn 剛体どうしの接触点集合の残差を測る(
    集合番号: usize,
    バッチ: &mut 接触拘束の二つのバッチ,
    動的剛体一覧: &mut [細分の動的剛体],
    剛体一覧: &[剛体],
) -> Result<(), 接触の工程エラー> {
    let 集合 = バッチ.剛体どうしの接触点集合を反復のために借りる(集合番号);
    let Some(先頭) = 集合.first() else {
        return Ok(());
    };
    let (識別子a, 識別子b) = (先頭.履歴の鍵().小さい方の剛体(), 先頭.履歴の鍵().大きい方の剛体());
    let 参加者a = 参加者を組む(動的剛体一覧, 剛体一覧, 識別子a)?;
    let 参加者b = 参加者を組む(動的剛体一覧, 剛体一覧, 識別子b)?;
    for 拘束 in 集合.iter_mut() {
        拘束.細分の終わりの接線の残差を測る(&参加者a, &参加者b);
    }
    let mut 連立 = 残差の変化を打ち消す仮の補正の連立::空で始める();
    for 拘束 in 集合.iter() {
        拘束.残差の変化を仮の補正の連立へ積む(&mut 連立, &参加者a, &参加者b);
    }
    let (補正a, 補正b) = 連立.二つの参加者への仮の補正を求める();
    仮の補正を積む(動的剛体一覧, 識別子a, &補正a);
    仮の補正を積む(動的剛体一覧, 識別子b, &補正b);
    Ok(())
}

// 起きている動的剛体だけがこの細分の予測を持つ。持たない剛体は動かせない参加者として測る。
fn 参加者を組む(
    動的剛体一覧: &[細分の動的剛体],
    剛体一覧: &[剛体],
    識別子: 剛体の識別子,
) -> Result<姿勢自由度の参加者, 接触の工程エラー> {
    let 台帳剛体 = 剛体一覧.get(識別子.配列添字()).ok_or(剛体エラー::剛体が登録されていない { 識別子 })?;
    Ok(match 動的剛体一覧.iter().find(|剛体| 剛体.識別子 == 識別子) {
        Some(剛体) => 姿勢自由度の参加者::動的(*剛体.予測.配置(), 台帳剛体.質量特性()),
        None => 姿勢自由度の参加者::動かせない(*台帳剛体.配置()),
    })
}

fn 仮の補正を積む(
    動的剛体一覧: &mut [細分の動的剛体], 識別子: 剛体の識別子, 補正: &速度の再構成だけが読む仮の補正
) {
    let Some(剛体) = 動的剛体一覧.iter_mut().find(|剛体| 剛体.識別子 == 識別子) else {
        return;
    };
    剛体.残差の変化を打ち消す仮の補正 = 剛体.残差の変化を打ち消す仮の補正.合わせる(補正);
}
