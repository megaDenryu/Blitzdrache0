//! 接触の空間と世界(判断11・23)。
//! 空間索引(粗い選別)と静的世界の相手・剛体の形状と材質を保持する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11」「判断23」。

use std::collections::BTreeMap;

use blitz_collision::dynamic_index::{動く形の空間索引, 重なりうる形の対};
use blitz_collision::shape::{任意姿勢の直方体, 大域の軸平行の直方体, 直方体の軸ごとの半分の長さ};

use super::pipeline_error::接触の工程エラー;
use super::substep_predict::始点と終点の直方体から大域の箱を求める;
use crate::contact::material_id::材質の識別子;
use crate::contact::minimum_thickness::形の最小の厚み;
use crate::contact::static_world_partner::静的世界の接触相手;
use crate::rigid_body::{剛体の識別子, 配置};

pub struct 接触の空間と世界 {
    空間索引: 動く形の空間索引,
    静的世界の相手一覧: Vec<(静的世界の接触相手, 任意姿勢の直方体)>,
    剛体の形状一覧: BTreeMap<剛体の識別子, 直方体の軸ごとの半分の長さ>,
    剛体の材質一覧: BTreeMap<剛体の識別子, 材質の識別子>,
}

impl 接触の空間と世界 {
    pub fn 生成する(空間索引: 動く形の空間索引) -> Self {
        Self {
            空間索引,
            静的世界の相手一覧: Vec::new(),
            剛体の形状一覧: BTreeMap::new(),
            剛体の材質一覧: BTreeMap::new(),
        }
    }

    pub fn 剛体を登録する(
        &mut self,
        識別子: 剛体の識別子,
        初期配置: &配置,
        半分の長さ: 直方体の軸ごとの半分の長さ,
        材質: 材質の識別子,
    ) -> Result<(), 接触の工程エラー> {
        let 大域箱 = 始点と終点の直方体から大域の箱を求める(初期配置, 初期配置, 半分の長さ)?;
        let 索引id = 識別子.空間索引の識別子へ写す();
        self.空間索引.形を1つ登録する(索引id, &大域箱)?;
        self.剛体の形状一覧.insert(識別子, 半分の長さ);
        self.剛体の材質一覧.insert(識別子, 材質);
        Ok(())
    }

    pub fn 静的世界の接触相手を登録する(&mut self, 相手: 静的世界の接触相手, 直方体: 任意姿勢の直方体) {
        self.静的世界の相手一覧.push((相手, 直方体));
    }

    pub fn 形状を引く(&self, 識別子: 剛体の識別子) -> Result<直方体の軸ごとの半分の長さ, 接触の工程エラー> {
        self.剛体の形状一覧
            .get(&識別子)
            .copied()
            .ok_or(接触の工程エラー::形状が登録されていない { 識別子 })
    }

    pub fn 材質を引く(&self, 識別子: 剛体の識別子) -> Result<材質の識別子, 接触の工程エラー> {
        self.剛体の材質一覧
            .get(&識別子)
            .copied()
            .ok_or(接触の工程エラー::材質が登録されていない { 識別子 })
    }

    /// 登録した形が最も薄い向きに持つ厚み(判断12)。3軸の半分の長さの最小を2倍した値であり、深い重なりを解く1細分の補正の上限になる。
    pub fn 形の最小の厚みを求める(&self, 識別子: 剛体の識別子) -> Result<形の最小の厚み, 接触の工程エラー> {
        let 半分 = self.形状を引く(識別子)?;
        let mut 最も薄い半分 = 半分.x();
        for 成分 in [半分.y(), 半分.z()] {
            if 成分 < 最も薄い半分 {
                最も薄い半分 = 成分;
            }
        }
        Ok(形の最小の厚み::生成する(最も薄い半分 * 2.0)?)
    }

    pub fn 静的世界の相手一覧(&self) -> &[(静的世界の接触相手, 任意姿勢の直方体)] {
        &self.静的世界の相手一覧
    }

    pub fn 形の箱を更新する(
        &mut self, 識別子: 剛体の識別子, 大域箱: &大域の軸平行の直方体
    ) -> Result<(), 接触の工程エラー> {
        self.空間索引.形の箱を更新する(識別子.空間索引の識別子へ写す(), 大域箱)?;
        Ok(())
    }

    pub fn 重なりうる形の対を集める(&mut self, 対一覧: &mut Vec<重なりうる形の対>) -> Result<(), 接触の工程エラー> {
        self.空間索引.重なりうる形の対を集める(対一覧)?;
        Ok(())
    }
}
