//! 細分の速度段階の工程(判断14)。
//! 速度再構成の後に、動摩擦と反発の衝撃を巡回数だけ解く。

use super::pipeline_error::接触の工程エラー;
use super::pipeline_solver::接触の解法ソルバー;
use super::substep_predict::細分の動的剛体;
use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::island::接触島;
use crate::contact::solver_quality::接触を解く品質の設定;
use crate::contact::velocity_stage::{接触の速度段階の結果, 接触点の法線の相対速度を求める};
use crate::rigid_body::{剛体, 剛体エラー};
use crate::rigid_xpbd::姿勢自由度の参加者;

impl 接触の解法ソルバー {
    pub(super) fn 速度段階を解く(
        &self,
        品質: &接触を解く品質の設定,
        島一覧: &[接触島],
        バッチ: &mut 接触拘束の二つのバッチ,
        動的剛体一覧: &mut [細分の動的剛体],
        剛体一覧: &[剛体],
    ) -> Result<(), 接触の工程エラー> {
        let 巡回数 = 品質.速度段階の巡回数();
        for 巡 in 0..巡回数 {
            let 初回 = 巡 == 0;
            for 島 in 島一覧 {
                self.島の静的世界の速度段階を解く(島, バッチ, 動的剛体一覧, 剛体一覧, 初回)?;
                self.島の剛体どうしの速度段階を解く(島, バッチ, 動的剛体一覧, 剛体一覧, 初回)?;
            }
        }
        Ok(())
    }

    fn 島の静的世界の速度段階を解く(
        &self,
        島: &接触島,
        バッチ: &mut 接触拘束の二つのバッチ,
        動的剛体一覧: &mut [細分の動的剛体],
        剛体一覧: &[剛体],
        初回: bool,
    ) -> Result<(), 接触の工程エラー> {
        let 静的区間 = 島.剛体と静的世界の接触拘束の区間();
        for 拘束 in 静的区間.可変スライスを切り出す(バッチ.剛体と静的世界の接触拘束を反復のために借りる()) {
            if !拘束.法線反力が在るか() {
                continue;
            }
            let id = 拘束.引数().剛体;
            let Some(剛体) = 動的剛体一覧.iter_mut().find(|b| b.識別子 == id) else {
                continue;
            };
            let 台帳剛体 = 剛体一覧.get(id.配列添字()).ok_or(剛体エラー::剛体が登録されていない { 識別子: id })?;
            let 参加者 = 姿勢自由度の参加者::動的(*剛体.予測.配置(), 台帳剛体.質量特性());
            let 参加点a = 拘束.速度段階の剛体の参加点(&参加者, 剛体.予測の運動状態);
            let 参加点b = 拘束.速度段階の静的世界の参加点();
            let 相対速度 = 接触点の法線の相対速度を求める(参加点a, 参加点b, 拘束.引数().接触法線);
            let 条件 = 拘束.速度段階の条件を組む(相対速度);
            let 結果 = if 初回 {
                self.速度段階.一点へ適用する(参加点a, 参加点b, 条件)
            } else {
                self.速度段階.一点へ反発だけ適用する(参加点a, 参加点b, 条件)
            };
            if let 接触の速度段階の結果::衝撃を適用した {
                適用後のaの運動状態,
            ..
            } = 結果
            {
                剛体.予測の運動状態 = 適用後のaの運動状態;
            }
        }
        Ok(())
    }
}
