//! 混合連立の求解ごとに、固有の向きが偽の固有値の下限のどれだけ上に居るかを溜める数え(Issue #103の段階A2の計測3。
//! 試験と計器の専用)。解法の計器(`solver_gauge`)から分けているのは、こちらが分布だけを溜める受け皿であり、
//! あちらが当て方と解いた回数と受理の破れを束ねる型だからである。
//! 数えるかどうかの印を分布の並びと同じ型が持つのは、この2つが同時に立ち同時に空になるためである。印を持つのは、
//! 1件を数えるたびに勝った有効集合の探索をもう一度走らせるためであり、印の無い試験の実行が遅くならないようにする。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use crate::contact::normal_tangential_system::{
    偽の固有値の下限に対する固有の向きの分布, 接触点集合の法線と接線の連立
};

/// 求解ごとの固有の向きの分布を、数える印が立っているあいだだけ溜める受け皿。
pub(super) struct 固有の向きの分布の数え {
    数えるか: bool,
    溜まった分布: Vec<偽の固有値の下限に対する固有の向きの分布>,
}

impl 固有の向きの分布の数え {
    pub(super) fn 零から始める() -> Self {
        Self {
            数えるか: false,
            溜まった分布: Vec::new(),
        }
    }

    /// 連立1つの分布を数える。印が立っていないか、相補条件を満たす有効集合が定まらなければ何もしない。
    pub(super) fn 一件を数える(&mut self, 連立: &接触点集合の法線と接線の連立) {
        if !self.数えるか {
            return;
        }
        let Some(内訳) = 連立.定まった解の内訳を読む() else {
            return;
        };
        self.溜まった分布.push(偽の固有値の下限に対する固有の向きの分布::内訳から読む(&内訳));
    }

    /// 数える印を立て、それまでに溜まった分布を取り出して空にする。計器が刻みごとに呼ぶ唯一の口である。
    pub(super) fn 数え始めて溜まった分を読む(&mut self) -> Vec<偽の固有値の下限に対する固有の向きの分布> {
        self.数えるか = true;
        std::mem::take(&mut self.溜まった分布)
    }
}
