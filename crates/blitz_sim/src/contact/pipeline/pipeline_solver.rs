//! 接触の解法ソルバー(判断9・12・13・14・17)。
//! 拘束反復・速度再構成・速度段階を解く。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断9」「判断12」「判断13」「判断14」「判断17」。

use super::pipeline_error::接触の工程エラー;
use super::substep_predict::細分の動的剛体;
use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::island::接触島;
use crate::contact::solver_quality::接触を解く品質の設定;
use crate::contact::velocity_stage::接触の速度段階;
use crate::rigid_body::{一刻みの入力, 剛体, 質量特性, 運動状態, 配置};
use crate::rigid_xpbd::{予測の状態, 前の状態, 細分の予測器};
use crate::xpbd::刻み幅;

pub struct 接触の解法ソルバー {
    pub(super) 予測器: 細分の予測器,
    pub(super) 速度段階: 接触の速度段階,
}

impl 接触の解法ソルバー {
    pub fn 生成する(予測器: 細分の予測器, 速度段階: 接触の速度段階) -> Self {
        Self { 予測器, 速度段階 }
    }

    pub fn 動的剛体を予測する(
        &self,
        配置: &配置,
        速度: &運動状態,
        特性: &質量特性,
        入力: &一刻みの入力,
    ) -> (前の状態, 予測の状態, 運動状態) {
        self.予測器.動的剛体を予測する(配置, 速度, 特性, 入力)
    }

    pub(in crate::contact::pipeline) fn 反復と再構成と速度段階を解く(
        &self,
        品質: &接触を解く品質の設定,
        細分の刻み幅: 刻み幅,
        バッチ: &mut 接触拘束の二つのバッチ,
        島一覧: &[接触島],
        動的剛体一覧: &mut [細分の動的剛体],
        剛体一覧: &mut [剛体],
    ) -> Result<(), 接触の工程エラー> {
        for _ in 0..品質.位置の反復回数() {
            for 島 in 島一覧 {
                self.島を一回反復する(島, バッチ, 動的剛体一覧, 剛体一覧)?;
            }
        }
        for 剛体 in 動的剛体一覧.iter_mut() {
            剛体.予測の運動状態 = 剛体.前の状態.確定した配置から速度を再構成する(剛体.予測.配置(), 細分の刻み幅);
        }
        self.速度段階を解く(品質, 島一覧, バッチ, 動的剛体一覧, 剛体一覧)?;
        for 剛体 in 動的剛体一覧.iter() {
            if let Some(対象) = 剛体一覧.get_mut(剛体.識別子.配列添字()) {
                対象.配置と速度を書き換える(*剛体.予測.配置(), 剛体.予測の運動状態)?;
            }
        }
        Ok(())
    }

    fn 島を一回反復する(
        &self,
        島: &接触島,
        バッチ: &mut 接触拘束の二つのバッチ,
        動的剛体一覧: &mut [細分の動的剛体],
        剛体一覧: &[剛体],
    ) -> Result<(), 接触の工程エラー> {
        let 静的区間 = 島.剛体と静的世界の接触点集合の区間();
        for 集合番号 in 静的区間.開始()..静的区間.終了() {
            let 集合 = バッチ.剛体と静的世界の接触点集合を反復のために借りる(集合番号);
            self.静的世界の接触点集合を一回反復する(集合, 動的剛体一覧, 剛体一覧)?;
        }
        let 剛体間区間 = 島.剛体どうしの接触点集合の区間();
        for 集合番号 in 剛体間区間.開始()..剛体間区間.終了() {
            let 集合 = バッチ.剛体どうしの接触点集合を反復のために借りる(集合番号);
            self.剛体どうしの接触点集合を一回反復する(集合, 動的剛体一覧, 剛体一覧)?;
        }
        Ok(())
    }
}
