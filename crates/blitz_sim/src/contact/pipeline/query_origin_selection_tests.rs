//! 細分の工程が、剛体どうしの対の衝突の問い合わせの基準原点を識別子の小さい剛体の粗い位置に選ぶことの検査(判断3)。
//! 担当するのは、接触点集合を作る配置の一覧に識別子の大きい剛体が先に並んでいても、候補対から組んだ2つの参加者の
//! 基準原点がどちらも識別子の小さい剛体の粗い位置に等しく、大きい剛体の粗い位置とは違うことである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断3」の「衝突数学層へ形を渡す境界」

#![allow(clippy::unwrap_used)]

use blitz_collision::dynamic_index::{動く形の空間索引, 箱に持たせるゆとりの幅};
use blitz_collision::shape::直方体の軸ごとの半分の長さ;
use blitz_math::{キログラム, メートル, ワールド, 位置};

use super::contact_test_pipeline_scene::試験の材質;
use super::pipeline_contact_batch::{候補対の参加者を組む, 候補対の配置を探す};
use super::pipeline_space::接触の空間と世界;
use super::substep_placement::細分の予測の結果;
use crate::contact::broad_phase::剛体どうしの候補対;
use crate::contact::query_origin::衝突の問い合わせの基準原点;
use crate::rigid_body::{剛体の台帳, 剛体の識別子, 姿勢, 質量特性, 運動状態, 運動種別, 配置};

fn 高さに置いた配置(高さ: f32) -> 配置 {
    let 零 = メートル::生成する(0.0);
    配置::生成する(位置::<ワールド>::生成する(零, メートル::生成する(高さ), 零), 姿勢::恒等())
}

fn 半分の長さ() -> 直方体の軸ごとの半分の長さ {
    直方体の軸ごとの半分の長さ::生成する([メートル::生成する(0.5); 3]).unwrap()
}

// 一辺1メートルの動的な箱を台帳と空間の両方へ登録する。識別子は登録の順に増える。
fn 箱を登録する(台帳: &mut 剛体の台帳, 空間: &mut 接触の空間と世界, 配置: 配置) -> 剛体の識別子 {
    let 一辺 = メートル::生成する(1.0);
    let 特性 = 質量特性::一様な箱(キログラム::生成する(1.0).unwrap(), 一辺, 一辺, 一辺).unwrap();
    let 識別子 = 台帳.登録する(配置, 特性, 運動種別::動的で始める(運動状態::静止())).unwrap();
    空間.剛体を登録する(識別子, &配置, 半分の長さ(), 試験の材質()).unwrap();
    識別子
}

#[test]
fn 剛体どうしの対の基準原点は配置一覧の並びに依らず識別子の小さい剛体の粗い位置である() {
    let mut 台帳 = 剛体の台帳::空();
    let mut 空間 = 接触の空間と世界::生成する(動く形の空間索引::ゆとりの幅から生成する(
        箱に持たせるゆとりの幅::人型と家具の大きさに見合う既定の幅(),
    ));
    let (上の配置, 下の配置) = (高さに置いた配置(20.5), 高さに置いた配置(19.5));
    let 小さい識別子 = 箱を登録する(&mut 台帳, &mut 空間, 上の配置);
    let 大きい識別子 = 箱を登録する(&mut 台帳, &mut 空間, 下の配置);
    let mut 予測の結果 = 細分の予測の結果::空から始める();
    予測の結果.動かない剛体を足す(大きい識別子, 下の配置, 半分の長さ(), 運動状態::静止());
    予測の結果.動かない剛体を足す(小さい識別子, 上の配置, 半分の長さ(), 運動状態::静止());
    let 対 = 剛体どうしの候補対::生成する(小さい識別子, 大きい識別子);
    let (aの配置, bの配置) = 候補対の配置を探す(&対, &予測の結果.接触点集合を作る配置一覧).unwrap();
    assert_eq!(aの配置.識別子, 小さい識別子);
    let (参加者a, 参加者b) = 候補対の参加者を組む(aの配置, bの配置, &空間).unwrap();
    let 小さい剛体の粗い位置 = 衝突の問い合わせの基準原点::剛体の粗い位置から選ぶ(&上の配置);
    assert_eq!(参加者a.識別子(), 小さい識別子);
    assert_eq!(参加者b.識別子(), 大きい識別子);
    assert_eq!(参加者a.基準原点(), 小さい剛体の粗い位置);
    assert_eq!(参加者b.基準原点(), 小さい剛体の粗い位置);
    assert_ne!(参加者b.基準原点(), 衝突の問い合わせの基準原点::剛体の粗い位置から選ぶ(&下の配置));
}
