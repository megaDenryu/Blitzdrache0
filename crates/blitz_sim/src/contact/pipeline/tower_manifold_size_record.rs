//! 箱10段の塔で、細分ごとの接触点集合の点の数と、有効集合を全走査したときの求解の回数を綴る計器(判断11・判断13)。
//! 担当するのは3つを数えることである。第1段と第2段の対の接触点の数が細分ごとに何点であったかの分布、
//! 全部の接触点集合について1細分あたり Σ 2の点の数乗 で決まる全走査の求解の回数、そして細分の総数である。
//! 合否は判定しない。
//! 全走査の求解の回数を数えるのは、有効集合の走査を点の数の階層で打ち切る変更(`normal_tangential_system`)が
//! 減らした仕事の量を、実行時間とは別に配置の側から測るためである。階層の走査が実際に解いた回数は、この計器
//! では数えられない(数えるには連立の型が計数の状態を持つ必要がある)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11」「判断13」。

#![cfg(test)]

use blitz_collision::contact_set::接触点の上限;

use super::tower_fixture::箱の塔の場面を作る;
use crate::contact::contact_batches::接触拘束の二つのバッチ;

const 綴る刻みの数: usize = 600;
const 綴る第1の剛体の添字: usize = 1;
const 綴る第2の剛体の添字: usize = 2;

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 塔の接触点集合の点の数と全走査の求解の回数を綴る() {
    let (mut 工程, mut 台帳, _, _) = 箱の塔の場面を作る(10, false);
    let mut 対の点の数ごとの細分数 = [0_usize; 接触点の上限 + 1];
    let mut 細分の数 = 0_usize;
    let mut 全走査の求解の回数の合計 = 0_u64;
    let mut 一細分の全走査の求解の回数の最大 = 0_u64;
    for 刻み in 0..綴る刻みの数 {
        let Ok(細分ごと) = 工程.一刻み進めて細分ごとのバッチを返す(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        for バッチ in &細分ごと {
            細分の数 += 1;
            対の点の数ごとの細分数[綴る対の接触点の数(バッチ)] += 1;
            let 回数 = 一細分の全走査の求解の回数(バッチ);
            全走査の求解の回数の合計 += 回数;
            一細分の全走査の求解の回数の最大 = 一細分の全走査の求解の回数の最大.max(回数);
        }
    }
    println!("細分の数 {細分の数}");
    println!("第1段と第2段の対の点の数ごとの細分数 {対の点の数ごとの細分数:?}");
    println!("全走査の求解の回数の合計 {全走査の求解の回数の合計}");
    println!("一細分の全走査の求解の回数の最大 {一細分の全走査の求解の回数の最大}");
}

// 綴る対の接触拘束の数。その対の接触点集合が無い細分では0である。
fn 綴る対の接触点の数(バッチ: &接触拘束の二つのバッチ) -> usize {
    バッチ
        .剛体どうしの接触拘束()
        .iter()
        .filter(|拘束| {
            let 引数 = 拘束.引数();
            (引数.剛体a.配列添字(), 引数.剛体b.配列添字()) == (綴る第1の剛体の添字, 綴る第2の剛体の添字)
        })
        .count()
}

// 有効集合を全走査したときに解く連立の数。接触点集合1つにつき2の点の数乗である。
fn 一細分の全走査の求解の回数(バッチ: &接触拘束の二つのバッチ) -> u64 {
    バッチ
        .剛体どうしの接触点集合の範囲()
        .iter()
        .chain(バッチ.剛体と静的世界の接触点集合の範囲())
        .map(|範囲| 1_u64 << 範囲.接触点の数())
        .sum()
}
