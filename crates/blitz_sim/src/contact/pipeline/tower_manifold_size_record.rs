//! 箱10段の塔で、接触点集合の点の数と有効集合の走査の費用を綴る計器(判断11・判断13)。
//! 担当するのは3つを数えることである。第1段と第2段の対の接触点の数が細分ごとに何点であったかの分布、
//! 有効集合の階層の走査が実際に解いた連立の回数、そして同じ場面で取りうる部分集合を全部走査していたならば
//! 解いたはずの回数である。合否は判定しない。
//! 2つの回数を対で数えるのは、片方だけでは費用の主張ができないためである。回数はどちらも解法の1回の求解ごとに
//! 揃って増えるため、位置の反復の回数も滑走中の集合が法線だけの連立へ落ちることも同じように織り込まれている。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11」「判断13」。

#![cfg(test)]

use blitz_collision::contact_set::接触点の上限;

use super::tower_fixture::箱の塔の場面を作る;
use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::normal_tangential_system::部分集合を解いた回数;

const 綴る刻みの数: usize = 600;
const 綴る第1の剛体の添字: usize = 1;
const 綴る第2の剛体の添字: usize = 2;

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 塔の接触点集合の点の数と有効集合の走査の費用を綴る() {
    let (mut 工程, mut 台帳, _, _) = 箱の塔の場面を作る(10, false);
    let mut 対の点の数ごとの細分数 = [0_usize; 接触点の上限 + 1];
    let mut 細分の数 = 0_usize;
    let mut 解いた回数の合計 = 部分集合を解いた回数::零();
    let mut 一刻みの階層の走査の最大 = 0_u64;
    let mut 一刻みの全走査の最大 = 0_u64;
    for 刻み in 0..綴る刻みの数 {
        let Ok(細分ごと) = 工程.一刻み進めて細分ごとのバッチを返す(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        for バッチ in &細分ごと {
            細分の数 += 1;
            対の点の数ごとの細分数[綴る対の接触点の数(バッチ)] += 1;
        }
        let 一刻みの回数 = 工程.解いた回数の累計を読んで零に戻す();
        一刻みの階層の走査の最大 = 一刻みの階層の走査の最大.max(一刻みの回数.階層の走査が解いた数());
        一刻みの全走査の最大 = 一刻みの全走査の最大.max(一刻みの回数.全走査ならば解く数());
        解いた回数の合計 = 解いた回数の合計.足す(一刻みの回数);
    }
    println!("細分の数 {細分の数}");
    println!("第1段と第2段の対の点の数ごとの細分数 {対の点の数ごとの細分数:?}");
    println!("階層の走査が解いた連立の回数の合計 {}", 解いた回数の合計.階層の走査が解いた数());
    println!("全走査ならば解いたはずの回数の合計 {}", 解いた回数の合計.全走査ならば解く数());
    println!("一刻みの最大 階層の走査 {一刻みの階層の走査の最大} 全走査 {一刻みの全走査の最大}");
}

// 綴る対の接触拘束の数。その対の接触点集合が無い細分では0である。
fn 綴る対の接触点の数(バッチ: &接触拘束の二つのバッチ) -> usize {
    バッチ
        .剛体どうしの接触拘束()
        .iter()
        .filter(|拘束| {
            let 引数 = 拘束.引数();
            (引数.剛体a.配列添字(), 引数.剛体b.配列添字()) == (綴る第1の剛体の添字, 綴る第2の剛体の添字)
        })
        .count()
}
