//! 複数の剛体を含む接触島が休止して再開することの受入検査(判断18)。
//! 箱10段の塔でこれを固定できないのは、上下に積んだ同じ大きさの箱どうしの接触点集合の特徴の識別が細分ごとに
//! 入れ替わり、静止摩擦の錨が毎細分置き直されて島が静穏にならないためである(Issue #75。実測は
//! `_doc/計測/剛体の接触の休止の切り分け_2026-09-05.md`)。側面で接する2つの箱は荷重を伝えないため、その欠陥を
//! 踏まずに休止まで到達する。休止機構そのものが完成していることをこの1本が示す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use blitz_math::{ニュートン秒, 衝撃};

use super::side_by_side_fixture::側面で接する二つの箱の場面を作る;
use crate::rigid_body::休止から起きた理由;

// 2026-09-05の実測では735刻みで休止する。刻みの上限をその1.4倍に置く。
const 休止を待つ刻み数: usize = 1000;

#[test]
fn 側面で接する二つの箱の島が休止し衝撃で二つとも起きる() {
    let (mut 工程, mut 台帳, 箱一覧) = 側面で接する二つの箱の場面を作る();
    let mut 最初に休止した刻み = [None, None];
    for 刻み in 0..休止を待つ刻み数 {
        if let Err(誤り) = 工程.一刻み進める(&mut 台帳) {
            panic!("刻み {刻み} で一刻み進めるエラー: {誤り:?}");
        }
        for (順, &識別子) in 箱一覧.iter().enumerate() {
            let Ok(剛体) = 台帳.参照する(識別子) else {
                panic!("箱の参照に失敗した: {識別子:?}");
            };
            if 剛体.実行状態().休止しているか() && 最初に休止した刻み[順].is_none() {
                最初に休止した刻み[順] = Some(刻み);
            }
        }
        if 最初に休止した刻み.iter().all(Option::is_some) {
            break;
        }
    }
    let [左が休止した刻み, 右が休止した刻み] = 最初に休止した刻み;
    assert!(
        左が休止した刻み.is_some() && 右が休止した刻み.is_some(),
        "{休止を待つ刻み数}刻み以内に側面で接する2つの箱が休止しなかった: {最初に休止した刻み:?}"
    );
    assert_eq!(
        左が休止した刻み, 右が休止した刻み,
        "1つの島に属する2つの箱が別々の刻みで休止した: {最初に休止した刻み:?}"
    );

    let p = 衝撃::成分から生成する(ニュートン秒::生成する(0.0), ニュートン秒::生成する(5.0), ニュートン秒::生成する(0.0));
    let Ok(()) = 台帳.重心へ衝撃を加える(箱一覧[0], p) else {
        panic!("衝撃を加えられなかった");
    };
    let Ok(()) = 工程.一刻み進める(&mut 台帳) else {
        panic!("衝撃の後の一刻みに失敗した");
    };
    for &識別子 in &箱一覧 {
        let Ok(剛体) = 台帳.参照する(識別子) else {
            panic!("箱の参照に失敗した: {識別子:?}");
        };
        assert!(剛体.実行状態().起きているか(), "衝撃の後に起きていない箱がある: {識別子:?}");
    }
    let Ok(衝撃を受けた箱) = 台帳.参照する(箱一覧[0]) else {
        panic!("箱の参照に失敗した");
    };
    assert_eq!(
        衝撃を受けた箱.実行状態().直近に休止から起きた理由(),
        Some(休止から起きた理由::作用の投入),
        "衝撃を受けた箱が作用の投入以外の理由を記録している"
    );
}
