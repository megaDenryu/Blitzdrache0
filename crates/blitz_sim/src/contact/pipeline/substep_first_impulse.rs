//! 刻みの最初の細分でだけ動く工程(判断6・19)。刻みの初めに取り出した衝撃と回転衝撃を、最初の細分の予測の前に
//! 1度だけ速度へ足す。
//! 細分1本の工程(`pipeline_substep`)から分けているのは、呼ばれるタイミングが刻みに1度と細分ごとで違うためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断6: 永続状態と一刻みの作用を分け、任意点への作用は剛体の側が回転力へ写す」

use super::pipeline_def::剛体の接触の一刻みの工程;
use super::pipeline_error::接触の工程エラー;
use crate::rigid_body::{一度だけ適用する衝撃, 休止から起きた理由, 剛体の台帳, 剛体の識別子};
use crate::rigid_xpbd::姿勢自由度の参加者;

impl 剛体の接触の一刻みの工程 {
    // 工程2で取り出した衝撃と回転衝撃を、最初の細分の予測の前に1度だけ速度へ足す(判断6)。
    pub(super) fn 最初の細分の衝撃を適用する(
        &self,
        台帳: &mut 剛体の台帳,
        衝撃一覧: &[(剛体の識別子, 一度だけ適用する衝撃)],
    ) -> Result<(), 接触の工程エラー> {
        for &(識別子, 衝撃) in 衝撃一覧 {
            let 剛体 = 台帳.参照する(識別子)?;
            let (配置, 特性, 速度) = (*剛体.配置(), *剛体.質量特性(), 剛体.速度()?);
            let 参加者 = 姿勢自由度の参加者::動的(配置, &特性);
            let 新しい速度 = 衝撃.運動状態へ適用する(速度, 参加者.逆質量(), 参加者.ワールドの逆慣性());
            if 新しい速度 != 速度 {
                self.直前の島
                    .契機を受けて島ごと起こす(識別子, 休止から起きた理由::作用の投入, 台帳.剛体一覧_mut());
            }
            台帳.書き換える(識別子)?.配置と速度を書き換える(配置, 新しい速度)?;
        }
        Ok(())
    }
}
