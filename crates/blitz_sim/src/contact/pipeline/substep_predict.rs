//! 細分の中の動的剛体の予測と空間索引の更新(判断8・11)。

use blitz_collision::shape::{任意姿勢の直方体, 大域の軸平行の直方体, 直方体の軸ごとの半分の長さ};
use blitz_math::{クォータニオン, ローカル, 位置};

use super::pipeline_error::接触の工程エラー;
use crate::contact::broad_phase::始点と終点を包む大域の箱を求める;
use crate::rigid_body::{剛体の識別子, 運動状態, 配置};
use crate::rigid_xpbd::{予測の状態, 前の状態};

/// 細分の中で予測した動的剛体の状態。
pub(super) struct 細分の動的剛体 {
    pub(super) 識別子: 剛体の識別子,
    pub(super) 前の状態: 前の状態,
    pub(super) 予測: 予測の状態,
    pub(super) 予測の運動状態: 運動状態,
}

pub(super) fn 直方体を組む(
    配置: &配置, 半分の長さ: 直方体の軸ごとの半分の長さ
) -> Result<任意姿勢の直方体, 接触の工程エラー> {
    let 重心 = 配置.重心の位置();
    let 中心 = 位置::<ローカル>::生成する(重心.x(), 重心.y(), 重心.z());
    let [x, y, z, w] = 配置.姿勢().境界用xyzw配列();
    let 回転 = クォータニオン::<ローカル, ローカル>::生成する(x, y, z, w)?;
    Ok(任意姿勢の直方体::生成する(中心, 回転, 半分の長さ)?)
}

pub(super) fn 始点と終点の直方体から大域の箱を求める(
    始点配置: &配置,
    終点配置: &配置,
    半分の長さ: 直方体の軸ごとの半分の長さ,
) -> Result<大域の軸平行の直方体, 接触の工程エラー> {
    let 始点の箱 = 直方体を組む(始点配置, 半分の長さ)?;
    let 終点の箱 = 直方体を組む(終点配置, 半分の長さ)?;
    Ok(始点と終点を包む大域の箱を求める(&始点の箱, &終点の箱))
}
