//! 細分の中の動的剛体の予測と空間索引の更新(判断8・11)。
//! 索引へ渡す大域の箱は、細分の始点と終点それぞれの粗い位置を衝突の問い合わせの基準原点にした相対の直方体の外接箱を
//! 大域原点から写して作り、二段の位置を単精度へ畳む経路を通らない(判断3)。

use blitz_collision::shape::{大域の軸平行の直方体, 直方体の軸ごとの半分の長さ};

use super::pipeline_error::接触の工程エラー;
use crate::contact::query_origin::{大域原点に相対な直方体, 衝突の問い合わせの基準原点};
use crate::rigid_body::{剛体の識別子, 運動状態, 配置};
use crate::rigid_xpbd::{予測の状態, 前の状態};

/// 細分の中で予測した動的剛体の状態。
pub(super) struct 細分の動的剛体 {
    pub(super) 識別子: 剛体の識別子,
    pub(super) 前の状態: 前の状態,
    pub(super) 予測: 予測の状態,
    pub(super) 予測の運動状態: 運動状態,
}

// 配置の粗い位置を基準原点にした相対の直方体と、その原点を大域へ写したもの。
fn 自分の粗い位置に相対な直方体を組む(
    配置: &配置,
    半分の長さ: 直方体の軸ごとの半分の長さ,
) -> Result<大域原点に相対な直方体, 接触の工程エラー> {
    let 基準原点 = 衝突の問い合わせの基準原点::剛体の粗い位置から選ぶ(配置);
    Ok(大域原点に相対な直方体::生成する(
        基準原点.剛体の相対の直方体を組む(配置, 半分の長さ)?,
        基準原点.大域の原点として読む(),
    ))
}

pub(super) fn 始点と終点の配置から大域の箱を求める(
    始点配置: &配置,
    終点配置: &配置,
    半分の長さ: 直方体の軸ごとの半分の長さ,
) -> Result<大域の軸平行の直方体, 接触の工程エラー> {
    Ok(自分の粗い位置に相対な直方体を組む(始点配置, 半分の長さ)?
        .始点と終点を包む大域の箱を求める(&自分の粗い位置に相対な直方体を組む(終点配置, 半分の長さ)?))
}
