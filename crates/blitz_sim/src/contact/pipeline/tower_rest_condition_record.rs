//! 箱10段の塔が休止しない原因を切り分ける計器(判断18)。静穏の4条件のうちどれが成立していないかを数える。
//! 4条件は、島の全部の動的剛体の速度と角速度が休止の閾値以下であること、滑走中の接触が無いこと、錨を置き直した
//! 接触が無いこと、全部の接触の食い込みが接触余白以下であることである。合否は判定しない。
//! 読める粒度が条件ごとに違う。滑走中と錨の置き直しと食い込みは細分ごとのバッチから細分の粒度で読めるが、剛体の
//! 速度は工程が刻みの末に書き戻すため刻みの粒度でしか読めない。食い込みも、細分の末の隔たりではなく生成時の
//! 符号付き貫通量である。したがってこの計器が答えるのは「どの条件が、どれだけの頻度で成立していないか」であって、
//! 静穏の判定そのものの再現ではない。
//! 錨の置き直しは接触が開始した細分と円錐を超えた細分の両方で立つため、特徴の識別の開始の割合の代わりに読む。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18」。

#![cfg(test)]

use super::tower_fixture::箱の塔の場面を作る;
use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::contact_thresholds::休止と判定する接触余白;
use crate::rigid_body::剛体の台帳;

const 綴る刻みの数: usize = 600;
const 綴る対の一覧: [(usize, usize); 2] = [(1, 2), (2, 3)];

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 塔が休止しない原因の静穏の四条件を綴る() {
    let (mut 工程, mut 台帳, _, _) = 箱の塔の場面を作る(10, false);
    let (mut 細分の数, mut 滑走中の細分, mut 錨を置き直した細分, mut 食い込みが余白を超えた細分) = (0, 0, 0, 0);
    let mut 運動が静穏でない刻み = 0;
    let mut 対ごとの拘束の数 = [0_usize; 2];
    let mut 対ごとの錨を置き直した拘束の数 = [0_usize; 2];
    for 刻み in 0..綴る刻みの数 {
        let Ok(細分ごと) = 工程.一刻み進めて細分ごとのバッチを返す(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        for バッチ in &細分ごと {
            細分の数 += 1;
            滑走中の細分 += usize::from(滑走中の拘束があるか(バッチ));
            錨を置き直した細分 += usize::from(錨を置き直した拘束があるか(バッチ));
            食い込みが余白を超えた細分 += usize::from(食い込みが余白を超えた拘束があるか(バッチ));
            対ごとの件数を数える(バッチ, &mut 対ごとの拘束の数, &mut 対ごとの錨を置き直した拘束の数);
        }
        運動が静穏でない刻み += usize::from(!全部の動的剛体の運動が静穏か(&台帳));
    }
    println!("細分の数 {細分の数} 刻みの数 {綴る刻みの数}");
    println!("滑走中の拘束がある細分 {滑走中の細分}");
    println!("錨を置き直した拘束がある細分 {錨を置き直した細分}");
    println!("生成時の食い込みが接触余白を超えた拘束がある細分 {食い込みが余白を超えた細分}");
    println!("刻みの末に運動が静穏でない動的剛体がある刻み {運動が静穏でない刻み}");
    for (番号, 対) in 綴る対の一覧.iter().enumerate() {
        println!(
            "対 {対:?} 拘束の総数 {} 錨を置き直した拘束の数 {}",
            対ごとの拘束の数[番号], 対ごとの錨を置き直した拘束の数[番号]
        );
    }
}

fn 滑走中の拘束があるか(バッチ: &接触拘束の二つのバッチ) -> bool {
    バッチ.剛体どうしの接触拘束().iter().any(|拘束| 拘束.静止摩擦の解の状態().滑走中か())
        || バッチ.剛体と静的世界の接触拘束().iter().any(|拘束| 拘束.静止摩擦の解の状態().滑走中か())
}

fn 錨を置き直した拘束があるか(バッチ: &接触拘束の二つのバッチ) -> bool {
    バッチ
        .剛体どうしの接触拘束()
        .iter()
        .any(|拘束| 拘束.静止摩擦の解の状態().錨を置き直したか())
        || バッチ
            .剛体と静的世界の接触拘束()
            .iter()
            .any(|拘束| 拘束.静止摩擦の解の状態().錨を置き直したか())
}

fn 食い込みが余白を超えた拘束があるか(バッチ: &接触拘束の二つのバッチ) -> bool {
    let 余白 = 休止と判定する接触余白().値();
    バッチ
        .剛体どうしの接触拘束()
        .iter()
        .any(|拘束| 拘束.引数().生成時の符号付き貫通量.長さ().値() > 余白)
        || バッチ
            .剛体と静的世界の接触拘束()
            .iter()
            .any(|拘束| 拘束.引数().生成時の符号付き貫通量.長さ().値() > 余白)
}

fn 全部の動的剛体の運動が静穏か(台帳: &剛体の台帳) -> bool {
    台帳.剛体一覧().iter().all(|剛体| 剛体.運動種別().速度().is_none() || 剛体.運動が静穏か())
}

fn 対ごとの件数を数える(バッチ: &接触拘束の二つのバッチ, 拘束の数: &mut [usize; 2], 錨の数: &mut [usize; 2]) {
    for 拘束 in バッチ.剛体どうしの接触拘束() {
        let 引数 = 拘束.引数();
        let 組 = (引数.剛体a.配列添字(), 引数.剛体b.配列添字());
        let Some(番号) = 綴る対の一覧.iter().position(|対| *対 == 組) else {
            continue;
        };
        拘束の数[番号] += 1;
        錨の数[番号] += usize::from(拘束.静止摩擦の解の状態().錨を置き直したか());
    }
}
