//! 坂の上の2段の動的な箱を受理0.5・1・2倍と旧の形で刻みごとに読む計器(親の2026-09-12の指示による診断)。刻みごとに
//! 受理の判定の結末の内訳(受理した・円錐を超えた・数値の契約を破った(理由))を綴り、(B1)の破れを残差と許容差の比が
//! 10未満の群と10以上の群に分けて数え、群ごとに破れた行の C_t と δ・勝った有効集合・捨てた向きの数を綴る。合否は判定しない。
//! 600刻みを通した下の箱の坂の面に対する傾きの正接の最大値も綴り、箱が転倒していないことを数で示す。1回の走行と
//! 読み取りの手順は子モジュール(`run`)が持つ。場面は `stacked_slope_fixture` が組む。
//! 実行は `cargo test -p blitz_sim --release 落ちた場面の刻み_坂の上の二段の箱 -- --ignored --nocapture` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

mod run;

use crate::contact::normal_tangential_system::{
    接線の行への許容差の適用規則, 解けたと見なす許容差の倍率, 試験の許容差の適用規則
};

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 落ちた場面の刻み_坂の上の二段の箱を受理の倍率と旧の形で綴る() {
    for 倍率 in [0.5, 1.0, 2.0] {
        let 適用規則 =
            試験の許容差の適用規則::本番と同じ適用規則().受理の倍率を差し替える(解けたと見なす許容差の倍率::比から生成する(倍率));
        run::一つの適用規則を綴る(&適用規則.綴り(), 適用規則);
    }
    let 旧の形 = 試験の許容差の適用規則::受理の倍率だけを振る(解けたと見なす許容差の倍率::既定で生成する());
    let 旧の形の行への適用規則 =
        接線の行への許容差の適用規則::全部の拘束行を追加し右辺に受理の倍率を掛けた許容差を残す;
    assert_eq!(旧の形.行への適用規則(), 旧の形の行への適用規則);
    run::一つの適用規則を綴る(&旧の形.綴り(), 旧の形);
}
