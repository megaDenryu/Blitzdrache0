//! 段階Cの検収で落ちた坂の上の2段の箱(受理0.5倍)を刻みごとに読む計器(親の指示による診断)。刻みごとに、受理の判定の
//! 結末の内訳(受理した・円錐を超えた・数値の契約を破った(理由))と、最初の数刻みは結末の並び(細分×反復×接触点集合の
//! 順)を綴る。合否は判定しない。場面は `stacked_slope_fixture` が組む。
//! 実行は `cargo test -p blitz_sim --release 落ちた場面の刻み_坂の上の二段の箱 -- --ignored --nocapture` である。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

use std::collections::BTreeMap;

use super::stacked_slope_fixture::坂の上の二段の箱の場面;
use super::stacked_slope_spec::原点;
use crate::contact::friction_coefficient::摩擦係数;
use crate::contact::normal_tangential_system::{
    受理の契約を破った理由, 混合連立の受理の結果, 解けたと見なす許容差の倍率, 試験の許容差の当て方
};

const 綴る刻みの数: usize = 600;
const 並びを綴る刻みの数: usize = 3;
const 内訳を綴る刻みの数: usize = 40;

fn 結末の綴り(結果: &混合連立の受理の結果) -> String {
    match 結果 {
        混合連立の受理の結果::受理した => "受理".to_owned(),
        混合連立の受理の結果::円錐を超えた => "円錐".to_owned(),
        混合連立の受理の結果::数値の契約を破った(理由) => match 理由 {
            受理の契約を破った理由::相補条件を満たさない => "B2".to_owned(),
            _ => format!("{}[{}]", 理由.契約の名前(), 理由.残差の綴り()),
        },
    }
}

fn 結末の鍵(結果: &混合連立の受理の結果) -> &'static str {
    match 結果 {
        混合連立の受理の結果::受理した => "受理",
        混合連立の受理の結果::円錐を超えた => "円錐",
        混合連立の受理の結果::数値の契約を破った(理由) => 理由.契約の名前(),
    }
}

fn 下り向きの変位(場面: &坂の上の二段の箱の場面) -> (f32, f32) {
    let 読む = |箱| {
        let Ok(剛体) = 場面.台帳.参照する(箱) else {
            panic!("箱が台帳に無い");
        };
        (剛体.配置().重心の位置() - 原点()).方向に沿う長さ(場面.幾何.下り向き()).値()
    };
    (読む(場面.下の箱), 読む(場面.上の箱))
}

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 落ちた場面の刻み_坂の上の二段の箱を受理零点五倍で綴る() {
    let Ok(摩擦) = 摩擦係数::生成する(0.6) else {
        panic!("摩擦係数を作れない");
    };
    let mut 場面 = 坂の上の二段の箱の場面::生成する(0.55, 摩擦);
    場面.工程.解法.計器.許容差の当て方を差し替える(
        試験の許容差の当て方::本番と同じ当て方().受理の倍率を差し替える(解けたと見なす許容差の倍率::比から生成する(0.5)),
    );
    let 初め = 下り向きの変位(&場面);
    for 刻み in 0..綴る刻みの数 {
        let Ok(_) = 場面.工程.一刻み進める(&mut 場面.台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        let 履歴 = 場面.工程.解法.計器.受理の判定の履歴を読んで空にする();
        let mut 内訳: BTreeMap<&'static str, usize> = BTreeMap::new();
        for 結果 in &履歴 {
            *内訳.entry(結末の鍵(結果)).or_insert(0) += 1;
        }
        let いま = 下り向きの変位(&場面);
        if 刻み < 内訳を綴る刻みの数 || 刻み % 100 == 99 {
            let 内訳の綴り: Vec<String> = 内訳.iter().map(|(鍵, 数)| format!("{鍵}={数}")).collect();
            println!(
                "  刻み{刻み} 判定{}件[{}] 下の箱の変位={:.3e} 上の箱の変位={:.3e}",
                履歴.len(),
                内訳の綴り.join(" "),
                いま.0 - 初め.0,
                いま.1 - 初め.1
            );
        }
        if 刻み < 並びを綴る刻みの数 {
            let 並び: Vec<String> = 履歴.iter().map(結末の綴り).collect();
            println!("    並び: {}", 並び.join(" | "));
        }
    }
}
