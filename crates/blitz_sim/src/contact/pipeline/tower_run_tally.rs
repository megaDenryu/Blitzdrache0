//! 塔を600刻み走らせるあいだに数える量とその数え方(Issue #59の第4段階の段階A3)。
//! 走らせる工程(`tower_row_admission_record`)から分けているのは、こちらが数える対象と数え方を持つ型であり、
//! あちらが場面を組んで当て方を差し替えて回す工程だからである。
//! 休止に至った刻みで解けなかった延べ数を写し取るのは、休止の前と後で退避の枝の走り方が違うためである。
//! 休止した島は接触点集合を作らないため、休止の後の細分では粘着の候補そのものが解かれない(判断11・判断18)。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::solver_gauge::解法の計器;
use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::contact_thresholds::休止と判定する接触余白;

/// 1つの当て方で走らせたあいだに数えた量。
pub(super) struct 塔の走行の数え {
    休止に至った刻み: Option<usize>,
    錨を置き直した拘束の延べ数: usize,
    最大の食い込み: f32,
    走った細分の数: usize,
    休止までの細分の数: usize,
    休止までの解けなかった延べ数: usize,
}

impl 塔の走行の数え {
    pub(super) fn 零から始める() -> Self {
        Self {
            休止に至った刻み: None,
            錨を置き直した拘束の延べ数: 0,
            最大の食い込み: 0.0,
            走った細分の数: 0,
            休止までの細分の数: 0,
            休止までの解けなかった延べ数: 0,
        }
    }

    /// 1刻みぶんの細分のバッチを数え、その刻みの末に全部の箱が休止していれば休止に至った刻みとして写し取る。
    pub(super) fn 一刻みを数える(
        &mut self, 細分ごと: &[接触拘束の二つのバッチ], 刻み: usize, 全部の箱が休止したか: bool, 計器: &解法の計器
    ) {
        for バッチ in 細分ごと {
            self.走った細分の数 += 1;
            self.錨を置き直した拘束の延べ数 += 錨を置き直した拘束の数(バッチ);
            self.最大の食い込み = self.最大の食い込み.max(最大の食い込み(バッチ));
        }
        if self.休止に至った刻み.is_none() && 全部の箱が休止したか {
            self.休止に至った刻み = Some(刻み);
            self.休止までの細分の数 = self.走った細分の数;
            self.休止までの解けなかった延べ数 = 計器.解けなかった結末().延べ数();
        }
    }

    /// 表へ綴る形。解けなかった延べ数は、休止の前と後に分けて綴る。
    pub(super) fn 綴り(&self, 計器: &解法の計器) -> String {
        let 全部の解けなかった延べ数 = 計器.解けなかった結末().延べ数();
        format!(
            "休止に至った刻み={:?} 細分={}本(うち休止まで{}本) 錨の置き直しの延べ数={} 解けず{}(休止まで{} 休止の後{} 精度不足{} {}) 最大の食い込み={:.4e} 余白={:.4e} 解いた回数={}",
            self.休止に至った刻み,
            self.走った細分の数,
            self.休止までの細分の数,
            self.錨を置き直した拘束の延べ数,
            全部の解けなかった延べ数,
            self.休止までの解けなかった延べ数,
            全部の解けなかった延べ数 - self.休止までの解けなかった延べ数,
            計器.解けなかった結末().表現の精度が不足した延べ数(),
            計器.受理の破れ().綴り(),
            self.最大の食い込み,
            休止と判定する接触余白().値(),
            計器.解いた回数の累計を読んで零に戻す().階層の走査が解いた数()
        )
    }
}

fn 錨を置き直した拘束の数(バッチ: &接触拘束の二つのバッチ) -> usize {
    バッチ
        .剛体どうしの接触拘束()
        .iter()
        .filter(|拘束| 拘束.静止摩擦の解の状態().錨を置き直したか())
        .count()
        + バッチ
            .剛体と静的世界の接触拘束()
            .iter()
            .filter(|拘束| 拘束.静止摩擦の解の状態().錨を置き直したか())
            .count()
}

fn 最大の食い込み(バッチ: &接触拘束の二つのバッチ) -> f32 {
    let 剛体どうし = バッチ
        .剛体どうしの接触拘束()
        .iter()
        .map(|拘束| 拘束.引数().生成時の符号付き貫通量.長さ().値());
    let 静的世界 = バッチ
        .剛体と静的世界の接触拘束()
        .iter()
        .map(|拘束| 拘束.引数().生成時の符号付き貫通量.長さ().値());
    剛体どうし.chain(静的世界).fold(0.0, f32::max)
}
