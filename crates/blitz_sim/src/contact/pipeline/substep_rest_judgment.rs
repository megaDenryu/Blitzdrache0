//! 細分の末に置く休止の判定(判断18)。細分1本の力学(`pipeline_substep`)から分けているのは、
//! こちらが触れるのが剛体の実行状態と静穏の継続時間だけであり、予測・接触点集合・反復のどの状態にも書き込まないためである。
//! 判定を刻みの末でなく細分の末で行うのは、判断18の静穏の4条件が細分の末の速度・貫通残差・錨で決まるためである。
//! 刻みの末で1度だけ判定すると、休止までに要る静穏の物理時間が細分数の倍だけ伸び、解法品質の設定が休止の時間意味を変える。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use super::pipeline_def::剛体の接触の一刻みの工程;
use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::island::接触島;
use crate::rigid_body::剛体の台帳;

/// 細分の末で休止の判定を行うかどうか。
/// `行わない` を試験のときだけ持つのは、休止が物理の結果を変えない最適化であること(判断18)を検査する反証の経路が唯一の作り手だからである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 休止の判定の実施 {
    行う,
    #[cfg(test)]
    行わない,
}

impl 剛体の接触の一刻みの工程 {
    /// この細分が組んだ島ごとに静穏を判定し、静穏の継続時間を細分1本ぶん進めるか零へ戻す。
    pub(super) fn 細分の末に休止を判定する(
        &self, 台帳: &mut 剛体の台帳, 島一覧: &[接触島], バッチ: &接触拘束の二つのバッチ
    ) {
        let 細分の刻み幅 = self.時間方針.細分の刻み幅();
        for 島 in 島一覧 {
            let 静穏か = 島.静穏か(バッチ, 台帳.剛体一覧());
            島.休止状態を更新する(静穏か, 細分の刻み幅, 台帳.剛体一覧_mut());
        }
    }
}
