//! 箱の塔の試験用場面のうち、床と箱を台帳と工程へ登録する部分(判断18)。
//! 工程の組み立て(`tower_scene`)と分けているのは、こちらが世界に物を置く工程であり、あちらが起動時の設定を決める工程だからである。

use blitz_collision::shape::直方体の軸ごとの半分の長さ;
use blitz_math::{キログラム, メートル, ワールド, 位置};

use super::pipeline_def::剛体の接触の一刻みの工程;
use super::tower_scene::{確定した細分数, 箱の塔の工程を組む, 細分数を指定して箱の塔の工程を組む, 試験の材質};
use crate::rigid_body::{剛体の台帳, 剛体の識別子, 姿勢, 質量特性, 運動状態, 運動種別, 配置};

pub fn 箱の塔の場面を作る(
    段数: u16,
    運動学的な床: bool,
) -> (剛体の接触の一刻みの工程, 剛体の台帳, Vec<剛体の識別子>, 剛体の識別子) {
    細分数を指定した箱の塔の場面を作る(確定した細分数, 段数, 運動学的な床)
}

pub fn 細分数を指定した箱の塔の場面を作る(
    細分の数: u32,
    段数: u16,
    運動学的な床: bool,
) -> (剛体の接触の一刻みの工程, 剛体の台帳, Vec<剛体の識別子>, 剛体の識別子) {
    let mut 台帳 = 剛体の台帳::空();
    let mut 工程 = if 細分の数 == 確定した細分数 {
        箱の塔の工程を組む()
    } else {
        細分数を指定して箱の塔の工程を組む(細分の数)
    };
    let mat = 試験の材質();
    let Ok(床質量) = キログラム::生成する(1000.0) else {
        panic!();
    };
    let Ok(床特性) = 質量特性::一様な箱(床質量, メートル::生成する(20.0), メートル::生成する(1.0), メートル::生成する(20.0))
    else {
        panic!();
    };
    let 床種別 = if 運動学的な床 {
        運動種別::運動学的で始める(運動状態::静止())
    } else {
        運動種別::静的
    };
    let 床配置 = 配置::生成する(
        位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(-0.5), メートル::生成する(0.0)),
        姿勢::恒等(),
    );
    let Ok(床id) = 台帳.登録する(床配置, 床特性, 床種別) else {
        panic!();
    };
    let Ok(床半分) =
        直方体の軸ごとの半分の長さ::生成する([メートル::生成する(10.0), メートル::生成する(0.5), メートル::生成する(10.0)])
    else {
        panic!();
    };
    let Ok(()) = 工程.剛体を登録する(床id, &床配置, 床半分, mat) else {
        panic!();
    };

    let Ok(箱質量) = キログラム::生成する(1.0) else {
        panic!();
    };
    let Ok(箱特性) = 質量特性::一様な箱(箱質量, メートル::生成する(1.0), メートル::生成する(1.0), メートル::生成する(1.0))
    else {
        panic!();
    };
    let Ok(箱半分) = 直方体の軸ごとの半分の長さ::生成する([メートル::生成する(0.5); 3]) else {
        panic!();
    };

    let mut 箱id一覧 = Vec::new();
    for i in 0..段数 {
        let y = 0.5 + f32::from(i) * 1.0;
        let 配置 = 配置::生成する(
            位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(y), メートル::生成する(0.0)),
            姿勢::恒等(),
        );
        let Ok(id) = 台帳.登録する(配置, 箱特性, 運動種別::動的で始める(運動状態::静止())) else {
            panic!();
        };
        let Ok(()) = 工程.剛体を登録する(id, &配置, 箱半分, mat) else {
            panic!();
        };
        箱id一覧.push(id);
    }
    (工程, 台帳, 箱id一覧, 床id)
}
