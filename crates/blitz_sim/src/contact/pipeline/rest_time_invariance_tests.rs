//! 休止までに要る連続静穏の物理時間が細分数に依らないことの検査(判断18・19)。
//! 休止の閾値を細分の個数で持つと、細分数という解法品質の設定を変えただけで休止までの物理時間が倍に伸びる。
//! この検査は同じ場面を細分数8と16で動かし、島が休止した細分が正本の物理時間0.125秒に当たる本数
//! (8なら60本目、16なら120本目)ちょうどであることを固定する。
//! 本数がちょうど閾値と等しいことは、1本手前の細分で休止していないことと、閾値の細分より遅れていないことの両方を言う。
//! 休止した刻みの番号でなく静穏が続いた細分の本数を読むのは、刻みの番号を比べると細分数の違いが解法の軌道そのものを変える
//! ことまで混ざり、閾値の時間意味だけを見られなくなるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use super::tower_fixture::細分数を指定した箱の塔の場面を作る;
use crate::contact::contact_thresholds::休止と判定する連続静穏の時間;
use crate::rigid_body::運動種別;

// 細分数と、閾値0.125秒がその細分数で何本に当たるかである。基本刻みは1/60秒であるから、本数は 0.125 × 60 × 細分数 である。
const 細分数と閾値の本数の一覧: [(u32, u32); 2] = [(8, 60), (16, 120)];
const 休止を待つ刻み数: usize = 600;
const 時間契約の許容誤差の秒数: f64 = 1.0e-9;

#[test]
fn 休止までに要る連続静穏の物理時間が細分数に依らない() {
    for (細分の数, 閾値の本数) in 細分数と閾値の本数の一覧 {
        閾値の本数が正本の物理時間と一致することを確かめる(細分の数, 閾値の本数);
        let (刻み, 本数) = 休止した刻みとそのときの静穏が続いた細分の本数を測る(細分の数);
        println!("細分数{細分の数}\t休止した刻み{刻み}\t休止した時点の静穏が続いた細分の本数{本数}");
        assert_eq!(
            本数, 閾値の本数,
            "細分数{細分の数}で休止した細分が閾値の{閾値の本数}本目でない(休止した刻み: {刻み})"
        );
    }
}

// 本数が閾値の物理時間を写したものであることを、本数 × 細分の刻み幅 が0.125秒に一致することで確かめる。
fn 閾値の本数が正本の物理時間と一致することを確かめる(細分の数: u32, 閾値の本数: u32) {
    let Ok(小さい整数) = u16::try_from(細分の数) else {
        panic!("細分数{細分の数}が大きすぎる");
    };
    let 細分の刻み幅の秒数 = 1.0 / (60.0 * f64::from(小さい整数));
    let 閾値の秒数 = f64::from(閾値の本数) * 細分の刻み幅の秒数;
    let 正本の秒数 = f64::from(休止と判定する連続静穏の時間().値());
    assert!(
        (閾値の秒数 - 正本の秒数).abs() < 時間契約の許容誤差の秒数,
        "細分数{細分の数}の閾値{閾値の本数}本が正本の物理時間{正本の秒数}秒に当たらない(その本数の物理時間: {閾値の秒数}秒)"
    );
}

fn 休止した刻みとそのときの静穏が続いた細分の本数を測る(細分の数: u32) -> (usize, u32) {
    let (mut 工程, mut 台帳, 箱id一覧, _) = 細分数を指定した箱の塔の場面を作る(細分の数, 1, false);
    let 箱id = 箱id一覧[0];
    for 刻み in 0..休止を待つ刻み数 {
        let Ok(()) = 工程.一刻み進める(&mut 台帳) else {
            panic!("細分数{細分の数}の刻み{刻み}で一刻み進めるのに失敗した");
        };
        let Ok(箱) = 台帳.参照する(箱id) else {
            panic!("箱の参照に失敗した");
        };
        if !箱.実行状態().休止しているか() {
            continue;
        }
        let 運動種別::動的 {
            静穏が続いた細分の本数,
        ..
        } = 箱.運動種別()
        else {
            panic!("休止した箱が動的でない");
        };
        return (刻み, 静穏が続いた細分の本数.本数());
    }
    panic!("細分数{細分の数}で床の上の箱1つが{休止を待つ刻み数}刻み以内に休止しなかった");
}
