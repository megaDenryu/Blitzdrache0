//! 休止までに要る連続静穏の物理時間が細分数に依らないことの検査(判断18・19)。
//! 休止の閾値を細分の個数で持つと、細分数という解法品質の設定を変えただけで休止までの物理時間が倍に伸びる。
//! この検査は同じ場面を細分数8と16で動かし、島が休止した時点の静穏の継続時間がどちらも閾値の0.125秒に収まることを固定する。
//! 静穏の継続時間そのものを読むのは、休止した刻みの番号を比べると、細分数の違いが解法の軌道そのものを変えることまで
//! 混ざってしまい、閾値の時間意味だけを見られなくなるためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use blitz_math::秒;

use super::tower_fixture::細分数を指定した箱の塔の場面を作る;
use crate::contact::contact_thresholds::休止と判定する連続静穏の時間;
use crate::rigid_body::運動種別;

const 比べる細分数一覧: [u32; 2] = [8, 16];
const 休止を待つ刻み数: usize = 600;

#[test]
fn 休止までに要る連続静穏の物理時間が細分数に依らない() {
    for 細分の数 in 比べる細分数一覧 {
        let (刻み, 継続時間) = 休止した刻みとそのときの静穏の継続時間を測る(細分の数);
        let 閾値 = 休止と判定する連続静穏の時間().値();
        let 細分の刻み幅 = 細分の刻み幅の秒数(細分の数);
        assert!(
            継続時間.値() >= 閾値 && 継続時間.値() <= 閾値 + 細分の刻み幅,
            "細分数{細分の数}で休止した時点の静穏の継続時間{継続時間:?}が、閾値{閾値}秒から1細分ぶんの範囲に収まらない(休止した刻み: {刻み})"
        );
    }
}

fn 細分の刻み幅の秒数(細分の数: u32) -> f32 {
    let Ok(小さい整数) = u16::try_from(細分の数) else {
        panic!("細分数{細分の数}が大きすぎる");
    };
    1.0 / (60.0 * f32::from(小さい整数))
}

fn 休止した刻みとそのときの静穏の継続時間を測る(細分の数: u32) -> (usize, 秒) {
    let (mut 工程, mut 台帳, 箱id一覧, _) = 細分数を指定した箱の塔の場面を作る(細分の数, 1, false);
    let 箱id = 箱id一覧[0];
    for 刻み in 0..休止を待つ刻み数 {
        let Ok(()) = 工程.一刻み進める(&mut 台帳) else {
            panic!("細分数{細分の数}の刻み{刻み}で一刻み進めるのに失敗した");
        };
        let Ok(箱) = 台帳.参照する(箱id) else {
            panic!("箱の参照に失敗した");
        };
        if !箱.実行状態().休止しているか() {
            continue;
        }
        let 運動種別::動的 { 静穏の継続時間, .. } = 箱.運動種別() else {
            panic!("休止した箱が動的でない");
        };
        return (刻み, 静穏の継続時間.値());
    }
    panic!("細分数{細分の数}で床の上の箱1つが{休止を待つ刻み数}刻み以内に休止しなかった");
}
