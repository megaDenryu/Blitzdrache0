//! 細分数を変えたときの塔の定常の食い込みを測る計測(判断19)。合否を決める受入条件ではない。
//! 細分数を増やすと1基本刻みあたりに解法を適用する回数そのものが増えるため、4・8・16は計算量も収束の程度も同じ条件ではない。
//! 同じ食い込みを要求する検査は、細分数が硬さを変えないという主張の反証として強すぎる。本番設定の細分数16で塔が崩れない
//! ことは `tower_standing_tests` が受入条件として固定しており、この計測はその外側で解法の収束性の傾向だけを見る。
//! 走らせるには `cargo test -p blitz_sim -- --ignored 細分数` と打つ。実測の表は `_doc/計測/剛体の接触の細分数と収束_2026-09-05.md` にある。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」

use super::tower_fixture::細分数を指定した箱の塔の場面を作る;

// 定常を見るため、落ち着くまでの過渡を捨ててから最後の100刻みの食い込みの最大を測る。
const 過渡として捨てる刻み数: usize = 500;
const 定常を測る刻み数: usize = 100;
const 測る細分数一覧: [u32; 4] = [4, 8, 16, 32];

#[test]
#[ignore = "合否を決めない計測であり、走ると4つの細分数で600刻みずつ回すため常時の検証には重い"]
fn 細分数ごとの塔の定常の最大の食い込みを表にする() {
    println!("細分数\t定常の最大の食い込み(メートル)");
    for 細分の数 in 測る細分数一覧 {
        let 食い込み = 定常の最大の食い込みを測る(細分の数);
        println!("{細分の数}\t{食い込み:e}");
    }
}

fn 定常の最大の食い込みを測る(細分の数: u32) -> f32 {
    let (mut 工程, mut 台帳, 箱id一覧, _) = 細分数を指定した箱の塔の場面を作る(細分の数, 10, false);
    let mut 最大の食い込み = 0.0f32;
    for 刻み in 0..(過渡として捨てる刻み数 + 定常を測る刻み数) {
        let Ok(()) = 工程.一刻み進める(&mut 台帳) else {
            panic!("細分数{細分の数}の刻み{刻み}で一刻み進めるのに失敗した");
        };
        if 刻み < 過渡として捨てる刻み数 {
            continue;
        }
        let 高さ一覧: Vec<f32> = 箱id一覧
            .iter()
            .map(|&id| {
                let Ok(剛体) = 台帳.参照する(id) else {
                    panic!("箱の参照に失敗した");
                };
                剛体.配置().重心の位置().y().値()
            })
            .collect();
        let Some(&最下段) = 高さ一覧.first() else {
            panic!("箱が1つも登録されていない");
        };
        最大の食い込み = 最大の食い込み.max(0.5 - 最下段);
        for 対 in 高さ一覧.windows(2) {
            最大の食い込み = 最大の食い込み.max(1.0 - (対[1] - 対[0]));
        }
    }
    最大の食い込み
}
