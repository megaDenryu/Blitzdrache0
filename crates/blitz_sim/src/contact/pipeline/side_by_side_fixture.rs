//! 静的な床の上に、側面で接する箱を横一列に並べた試験用場面(判断17・18)。
//! 隣り合う箱は側面の接触で1つの接触島へ結ばれるため、複数の剛体を含む島の休止と再開を測る場面になる。
//! 箱の数を引数にするのは、島の端から端まで再開が届くかを測るのに3つ以上の列が要るためである(判断18・Issue #80)。
//! 箱を積み上げた場面(`tower_fixture`)と分けているのは、あちらが上下の面と面の接触で荷重を伝える場面であり、
//! こちらが荷重を伝えない側面の接触だけで島を結ぶ場面だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use blitz_collision::shape::直方体の軸ごとの半分の長さ;
use blitz_math::{キログラム, メートル, ワールド, 位置};

use super::contact_test_pipeline_scene::{試験の接触の一刻みの工程を組む, 試験の材質};
use super::pipeline_def::剛体の接触の一刻みの工程;
use crate::rigid_body::{剛体の台帳, 剛体の識別子, 姿勢, 質量特性, 運動状態, 運動種別, 配置};

const 箱の半分の長さ: f32 = 0.5;

pub fn 側面で接する箱の列の場面を作る(
    箱の数: u16,
) -> (剛体の接触の一刻みの工程, 剛体の台帳, Vec<剛体の識別子>) {
    let mut 台帳 = 剛体の台帳::空();
    let mut 工程 = 試験の接触の一刻みの工程を組む();
    let 床の形 = 半分の長さを作る(10.0, 0.5, 10.0);
    登録する(&mut 台帳, &mut 工程, 床の形, 1000.0, 重心を作る(0.0, -0.5), 運動種別::静的);
    let 箱の形 = 半分の長さを作る(箱の半分の長さ, 箱の半分の長さ, 箱の半分の長さ);
    let 列の左端 = -f32::from(箱の数 - 1) * 箱の半分の長さ;
    let mut 箱一覧 = Vec::new();
    for 順 in 0..箱の数 {
        let x = 列の左端 + f32::from(順) * 箱の半分の長さ * 2.0;
        let 種別 = 運動種別::動的で始める(運動状態::静止());
        箱一覧.push(登録する(&mut 台帳, &mut 工程, 箱の形, 1.0, 重心を作る(x, 箱の半分の長さ), 種別));
    }
    (工程, 台帳, 箱一覧)
}

fn 半分の長さを作る(x: f32, y: f32, z: f32) -> 直方体の軸ごとの半分の長さ {
    let Ok(形) = 直方体の軸ごとの半分の長さ::生成する([メートル::生成する(x), メートル::生成する(y), メートル::生成する(z)])
    else {
        panic!("半分の長さが正でない");
    };
    形
}

// 場面は奥行きの軸へは並べないため、重心の奥行きは常に0である。
fn 重心を作る(x: f32, y: f32) -> 位置<ワールド> {
    位置::<ワールド>::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(0.0))
}

fn 登録する(
    台帳: &mut 剛体の台帳,
    工程: &mut 剛体の接触の一刻みの工程,
    半分の長さ: 直方体の軸ごとの半分の長さ,
    質量: f32,
    重心: 位置<ワールド>,
    種別: 運動種別,
) -> 剛体の識別子 {
    let Ok(質量の値) = キログラム::生成する(質量) else {
        panic!("質量が正でない");
    };
    let 二倍 = |長さ: メートル| メートル::生成する(長さ.値() * 2.0);
    let Ok(特性) = 質量特性::一様な箱(質量の値, 二倍(半分の長さ.x()), 二倍(半分の長さ.y()), 二倍(半分の長さ.z()))
    else {
        panic!("質量特性を作れない");
    };
    let 配置 = 配置::生成する(重心, 姿勢::恒等());
    let Ok(識別子) = 台帳.登録する(配置, 特性, 種別) else {
        panic!("台帳へ登録できない");
    };
    let Ok(()) = 工程.剛体を登録する(識別子, &配置, 半分の長さ, 試験の材質()) else {
        panic!("工程へ登録できない");
    };
    識別子
}
