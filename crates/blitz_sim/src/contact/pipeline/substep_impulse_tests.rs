//! 衝撃が最初の細分だけで1度だけ適用されることの検査(判断7・19)。

use blitz_collision::dynamic_index::{動く形の空間索引, 箱に持たせるゆとりの幅};
use blitz_collision::shape::直方体の軸ごとの半分の長さ;
use blitz_math::{キログラム, ニュートン秒, メートル, メートル毎秒, ワールド, 位置, 秒, 衝撃};

use super::pipeline_def::剛体の接触の一刻みの工程;
use super::pipeline_history::接触履歴の保持;
use super::pipeline_policy::接触の品質と時間方針;
use super::pipeline_solver::接触の解法ソルバー;
use super::pipeline_space::接触の空間と世界;
use crate::constraint_graph::一様な加速度;
use crate::contact::material_id::材質の識別子;
use crate::contact::mixing_rule_builder::混合則の組み立て;
use crate::contact::solver_quality::接触を解く品質の設定;
use crate::contact::velocity_stage::接触の速度段階;
use crate::rigid_body::{剛体の台帳, 姿勢, 質量特性, 運動状態, 運動種別, 配置};
use crate::rigid_xpbd::{ジャイロ項の扱い, 細分の予測器, 細分数};
use crate::xpbd::刻み幅;

#[test]
fn 衝撃は最初の細分だけで一度だけ適用される() {
    let mut 台帳 = 剛体の台帳::空();
    let 基本秒 = 秒::生成する(1.0 / 60.0);
    let Ok(基本幅) = 刻み幅::生成する(基本秒) else {
        panic!();
    };
    let Ok(n) = 細分数::生成する(4) else {
        panic!();
    };
    let 細分秒 = 秒::生成する(1.0 / 240.0);
    let Ok(細分幅) = 刻み幅::生成する(細分秒) else {
        panic!();
    };
    let Ok(品質) = 接触を解く品質の設定::生成する(1, 1) else {
        panic!();
    };
    let 組み立て = 混合則の組み立て::生成する();
    let mat = 材質の識別子::生成する(0);
    let Ok(混合則) = 組み立て.組み立てる() else {
        panic!();
    };
    let 重力 = 一様な加速度::零();
    let 予測器 = 細分の予測器::生成する(細分幅, 重力, ジャイロ項の扱い::陰的に一段解く);
    let 速度段階 = 接触の速度段階::生成する(細分幅, メートル毎秒::生成する(0.01));
    let 空間索引 = 動く形の空間索引::ゆとりの幅から生成する(箱に持たせるゆとりの幅::人型と家具の大きさに見合う既定の幅());
    let mut 工程 = 剛体の接触の一刻みの工程::生成する(
        接触の品質と時間方針::生成する(基本幅, n, 細分幅, 品質, 混合則),
        接触の空間と世界::生成する(空間索引),
        接触履歴の保持::見込みの接触点の数で生成する(16),
        接触の解法ソルバー::生成する(予測器, 速度段階),
    );

    let Ok(質量) = キログラム::生成する(2.0) else {
        panic!();
    };
    let Ok(特性) = 質量特性::一様な箱(質量, メートル::生成する(1.0), メートル::生成する(1.0), メートル::生成する(1.0))
    else {
        panic!();
    };
    let Ok(半分) = 直方体の軸ごとの半分の長さ::生成する([メートル::生成する(0.5); 3]) else {
        panic!();
    };
    let 配置 = 配置::生成する(
        位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(10.0), メートル::生成する(0.0)),
        姿勢::恒等(),
    );
    let Ok(箱id) = 台帳.登録する(配置, 特性, 運動種別::動的で始める(運動状態::静止())) else {
        panic!();
    };
    let Ok(()) = 工程.剛体を登録する(箱id, &配置, 半分, mat) else {
        panic!();
    };

    // 10 N・s の衝撃を加える。質量2kgなので速度変化 Δv = 10 / 2 = 5 m/s
    let p = 衝撃::成分から生成する(ニュートン秒::生成する(10.0), ニュートン秒::生成する(0.0), ニュートン秒::生成する(0.0));
    let Ok(()) = 台帳.重心へ衝撃を加える(箱id, p) else {
        panic!();
    };

    let Ok(()) = 工程.一刻み進める(&mut 台帳) else {
        panic!();
    };

    let Ok(剛体) = 台帳.参照する(箱id) else {
        panic!();
    };
    let Ok(速度) = 剛体.速度() else {
        panic!();
    };
    let vx = 速度.並進速度().x().値();
    // 4細分すべてで適用されていたら 20 m/s になるが、最初の細分だけなので 5 m/s になる
    assert!((vx - 5.0).abs() < 1e-4, "期待値 5.0 に対して実測 {}", vx);
}
