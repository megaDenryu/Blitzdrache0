//! 箱10段の塔が立つことの検査(判断12・18)。
//! 塔が立つことと塔が休止することを別の検査にしているのは、1本にすると片方だけが未達のときに、何が達成できていないのかが
//! 検査の名前から読めないためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12」「判断18」。

use super::tower_fixture::箱の塔の場面を作る;
use crate::contact::contact_thresholds::休止と判定する接触余白;
use crate::rigid_body::{剛体の台帳, 剛体の識別子};

#[test]
fn 箱十段の塔が六百刻みのあいだ全部の接触の食い込みを接触余白以内に保つ() {
    let (mut 工程, mut 台帳, 箱id一覧, _) = 箱の塔の場面を作る(10, false);
    let 余白 = 休止と判定する接触余白().値();
    for 刻み in 0..600 {
        if let Err(誤り) = 工程.一刻み進める(&mut 台帳) {
            panic!("刻み {刻み} で一刻み進めるエラー: {誤り:?}");
        }
        let 高さ一覧 = 各段の重心の高さ(&台帳, &箱id一覧);
        let Some(&最下段) = 高さ一覧.first() else {
            panic!("箱が1つも登録されていない");
        };
        let 床への食い込み = 0.5 - 最下段;
        assert!(
            床への食い込み <= 余白,
            "刻み {刻み} の最下段の床への食い込み {床への食い込み} が接触余白 {余白} を超えた"
        );
        for (段, 対) in 高さ一覧.windows(2).enumerate() {
            let 食い込み = 1.0 - (対[1] - 対[0]);
            assert!(
                食い込み <= 余白,
                "刻み {刻み} の第{段}段と第{}段の食い込み {食い込み} が接触余白 {余白} を超えた",
                段 + 1
            );
        }
    }
}

// 判断12が状態の不変条件として置くのは接触1点の隔たりであり、最下段から数えた絶対の高さではない。
// 10段の塔の最上段の絶対の高さは、その下にある10箇所の接触の食い込みの和だけ沈むためである。
fn 各段の重心の高さ(台帳: &剛体の台帳, 箱id一覧: &[剛体の識別子]) -> Vec<f32> {
    箱id一覧
        .iter()
        .map(|&id| {
            let Ok(剛体) = 台帳.参照する(id) else {
                panic!("箱の参照に失敗した: {id:?}");
            };
            剛体.配置().重心の位置().y().値()
        })
        .collect()
}
