//! 物理刻み1本の統括工程(判断19)。構造変更の反映・作用の取り出し・細分の繰り返し・休止の判定・刻み境界の確定をこの順で行う。
//! 細分1本の中身は`pipeline_substep`が持つ。呼ばれる頻度が刻みごとと細分ごとで違い、扱う状態も刻みを跨ぐ側と細分の中だけの側に分かれる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」。

use super::pipeline_def::剛体の接触の一刻みの工程;
use super::pipeline_error::接触の工程エラー;
use super::step_actions::刻みの初めに取り出した作用;
use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::island::接触島;
use crate::contact::rest::剛体を起こす;
use crate::rigid_body::{休止から起きた理由, 剛体の台帳, 運動種別};

impl 剛体の接触の一刻みの工程 {
    // 遷移が履歴を捨てることの検査が、工程1だけを呼んで前後の件数を比べるための口。
    #[cfg(test)]
    pub(super) fn 遷移した剛体の履歴の件数(&self, 識別子: crate::rigid_body::剛体の識別子) -> usize {
        self.履歴.剛体を含む履歴の件数(識別子)
    }

    /// 基本刻みを1本進める。休止の判定を含む本番の経路である。
    pub fn 一刻み進める(&mut self, 台帳: &mut 剛体の台帳) -> Result<(), 接触の工程エラー> {
        self.休止の判定を選んで一刻み進める(台帳, true)
    }

    // 休止が物理の結果を変えない最適化であること(判断18)を検査するための、休止の判定だけを外した反証の経路。
    #[cfg(test)]
    pub(in crate::contact) fn 休止を判定せずに一刻み進める(
        &mut self, 台帳: &mut 剛体の台帳
    ) -> Result<(), 接触の工程エラー> {
        self.休止の判定を選んで一刻み進める(台帳, false)
    }

    fn 休止の判定を選んで一刻み進める(
        &mut self,
        台帳: &mut 剛体の台帳,
        休止を判定するか: bool,
    ) -> Result<(), 接触の工程エラー> {
        self.構造変更を反映する(台帳)?;
        let mut 作用 = self.作用を取り出す(台帳)?;
        let mut 最後の細分 = None;
        for _ in 0..self.時間方針.細分数().値() {
            最後の細分 = Some(self.一細分進める(台帳, &mut 作用)?);
        }
        if let (true, Some((島一覧, バッチ))) = (休止を判定するか, 最後の細分) {
            休止を判定する(台帳, &島一覧, &バッチ);
        }
        self.履歴.刻み境界の配置を確定する(台帳.剛体一覧());
        Ok(())
    }

    // 工程1: 積まれた運動種別の遷移を反映し、遷移した剛体の接触の履歴を捨てて島を起こす。
    pub(super) fn 構造変更を反映する(&mut self, 台帳: &mut 剛体の台帳) -> Result<(), 接触の工程エラー> {
        let mut 予約 = std::mem::take(台帳.遷移の予約());
        let 遷移一覧 = 予約.反映する(台帳.剛体一覧_mut(), self.時間方針.基本刻み幅().秒())?;
        *台帳.遷移の予約() = 予約;
        for &識別子 in &遷移一覧 {
            self.履歴.遷移した剛体の履歴を破棄する(識別子);
            剛体を起こす(識別子, 台帳.剛体一覧_mut(), 休止から起きた理由::運動種別の遷移);
        }
        Ok(())
    }

    // 工程2: 動的な剛体の蓄積器を空へ戻し、この刻みの入力と最初の細分だけへ渡す衝撃を受け取る。
    fn 作用を取り出す(&self, 台帳: &mut 剛体の台帳) -> Result<刻みの初めに取り出した作用, 接触の工程エラー> {
        let 動的な識別子一覧: Vec<_> = 台帳
            .剛体一覧()
            .iter()
            .filter(|剛体| matches!(剛体.運動種別(), 運動種別::動的 { .. }))
            .map(|剛体| 剛体.識別子())
            .collect();
        let mut 作用 = 刻みの初めに取り出した作用::空();
        for 識別子 in 動的な識別子一覧 {
            let (入力, 衝撃) = 台帳.作用を取り出す(識別子)?;
            作用.一つの剛体の作用を足す(識別子, 入力, 衝撃);
        }
        Ok(作用)
    }
}

// 最後の細分が組んだ島ごとに静穏を判定し、連続細分数を進めるか零へ戻す(判断18)。
fn 休止を判定する(台帳: &mut 剛体の台帳, 島一覧: &[接触島], バッチ: &接触拘束の二つのバッチ) {
    for 島 in 島一覧 {
        let 静穏か = 島.静穏か(バッチ, 台帳.剛体一覧());
        島.休止状態を更新する(静穏か, 台帳.剛体一覧_mut());
    }
}
