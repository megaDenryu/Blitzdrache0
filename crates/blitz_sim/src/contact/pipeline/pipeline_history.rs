//! 接触履歴の保持(判断16・19)。
//! 細分間および刻み境界を跨いで接触の累積インパルスや前配置などの履歴状態を保持する。
//! 細分の初めに前の細分の記録を新しい接触点集合へ配る工程は`pipeline_handover`が持つ。触れる状態が同じでも、
//! こちらが刻みを跨いで持つ状態の器であるのに対し、あちらは細分1本の初めに1度だけ走る工程である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断16」「判断19」。

use std::collections::BTreeMap;

use super::pipeline_error::接触の工程エラー;
use crate::contact::body_body_contact::剛体と剛体の接触拘束;
use crate::contact::body_static_contact::剛体と静的世界の接触拘束;
use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::history::{剛体と静的世界の接触の履歴, 剛体どうしの接触の履歴};
use crate::rigid_body::{剛体, 剛体の識別子, 配置};

pub struct 接触履歴の保持 {
    pub(super) 剛体どうしの履歴: 剛体どうしの接触の履歴,
    pub(super) 剛体と静的世界の履歴: 剛体と静的世界の接触の履歴,
    前の配置一覧: BTreeMap<剛体の識別子, 配置>,
}

impl 接触履歴の保持 {
    pub fn 見込みの接触点の数で生成する(見込みの接触点数: usize) -> Self {
        Self {
            剛体どうしの履歴: 剛体どうしの接触の履歴::見込みの接触点の数で生成する(見込みの接触点数),
            剛体と静的世界の履歴: 剛体と静的世界の接触の履歴::見込みの接触点の数で生成する(見込みの接触点数),
            前の配置一覧: BTreeMap::new(),
        }
    }

    pub fn 初期配置を記録する(&mut self, 識別子: 剛体の識別子, 配置: &配置) {
        self.前の配置一覧.insert(識別子, *配置);
    }

    pub fn 前の配置(&self, 識別子: 剛体の識別子) -> Option<&配置> {
        self.前の配置一覧.get(&識別子)
    }

    // 遷移した剛体の履歴が実際に捨てられたことを検査が観測する口。件数は2つの履歴の合計である。
    #[cfg(test)]
    pub(super) fn 剛体を含む履歴の件数(&self, 識別子: 剛体の識別子) -> usize {
        let 剛体どうし = self
            .剛体どうしの履歴
            .項目一覧()
            .iter()
            .filter(|項目| 項目.鍵().剛体を含むか(識別子))
            .count();
        let 静的世界 = self
            .剛体と静的世界の履歴
            .項目一覧()
            .iter()
            .filter(|項目| 項目.鍵().剛体を含むか(識別子))
            .count();
        剛体どうし + 静的世界
    }

    pub fn 遷移した剛体の履歴を破棄する(&mut self, 識別子: 剛体の識別子) {
        self.剛体どうしの履歴.項目を絞り込む(|鍵| !鍵.剛体を含むか(識別子));
        self.剛体と静的世界の履歴.項目を絞り込む(|鍵| !鍵.剛体を含むか(識別子));
    }

    pub fn 履歴を置き換える(&mut self, バッチ: &接触拘束の二つのバッチ) -> Result<(), 接触の工程エラー> {
        let mut 終わりの項目剛体: Vec<_> = バッチ
            .剛体どうしの接触拘束()
            .iter()
            .map(剛体と剛体の接触拘束::細分の終わりの履歴の項目)
            .collect();
        終わりの項目剛体.sort_unstable_by_key(|項目| 項目.鍵());
        self.剛体どうしの履歴.細分の終わりの記録で置き換える(&終わりの項目剛体)?;

        let mut 終わりの項目静的: Vec<_> = バッチ
            .剛体と静的世界の接触拘束()
            .iter()
            .map(剛体と静的世界の接触拘束::細分の終わりの履歴の項目)
            .collect();
        終わりの項目静的.sort_unstable_by_key(|項目| 項目.鍵());
        self.剛体と静的世界の履歴.細分の終わりの記録で置き換える(&終わりの項目静的)?;
        Ok(())
    }

    pub fn 刻み境界の配置を確定する(&mut self, 剛体一覧: &[剛体]) {
        for 剛体 in 剛体一覧 {
            self.前の配置一覧.insert(剛体.識別子(), *剛体.配置());
        }
    }
}
