//! (判断18。親の指示による診断)。刻みごとに、全部の箱が休止したか・錨を置き直した拘束の延べ数・滑走中の拘束の延べ数・
//! 生成時の食い込みの最大・第1段と第2段の対と第2段と第3段の対の接触点の数の分布(細分16本のうち何本が何点か)・
//! 刻みの末の面の隔たりを綴る。合否は判定しない(休止が正しいかは親が判定する)。
//! 実行は `cargo test -p blitz_sim --release 塔の休止の前後 -- --ignored --nocapture` である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use super::tower_fixture::箱の塔の場面を作る;
use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::contact::normal_tangential_system::{
    接線の行への許容差の適用規則, 解けたと見なす許容差の倍率, 試験の許容差の適用規則
};
use crate::rigid_body::{剛体の台帳, 剛体の識別子};

const 綴る刻みの数: usize = 60;
const 詳しく綴る刻み: (usize, usize) = (30, 50);
const 箱の一辺: f32 = 1.0;

fn 対の接触点の数の分布(細分ごと: &[接触拘束の二つのバッチ], 下: 剛体の識別子, 上: 剛体の識別子) -> String {
    let mut 本数 = [0_usize; 9];
    for バッチ in 細分ごと {
        let 点 = バッチ
            .剛体どうしの接触拘束()
            .iter()
            .filter(|拘束| (拘束.引数().剛体a, 拘束.引数().剛体b) == (下, 上))
            .count();
        本数[点.min(8)] += 1;
    }
    本数
        .iter()
        .enumerate()
        .filter(|(_, 数)| **数 > 0)
        .map(|(点, 数)| format!("{点}点={数}本"))
        .collect::<Vec<_>>()
        .join(",")
}

fn 面の隔たり(台帳: &剛体の台帳, 下: 剛体の識別子, 上: 剛体の識別子) -> f32 {
    let (Ok(下の剛体), Ok(上の剛体)) = (台帳.参照する(下), 台帳.参照する(上)) else {
        panic!("箱の参照に失敗した");
    };
    (上の剛体.配置().重心の位置() - 下の剛体.配置().重心の位置()).y().値() - 箱の一辺
}

fn 一つの適用規則を綴る(見出し: &str, 適用規則: 試験の許容差の適用規則) {
    let (mut 工程, mut 台帳, 箱id一覧, _) = 箱の塔の場面を作る(10, false);
    工程.解法.計器.許容差の適用規則を差し替える(適用規則);
    println!("[{見出し}] 刻み | 休止 | 錨の置き直し | 滑走中 | 最大の食い込み | 第1段と第2段の点の分布 | 隔たり | 第2段と第3段の点の分布 | 隔たり");
    for 刻み in 0..綴る刻みの数 {
        let Ok(細分ごと) = 工程.一刻み進めて細分ごとのバッチを返す(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        let 休止 = 箱id一覧
            .iter()
            .all(|&id| 台帳.参照する(id).is_ok_and(|剛体| 剛体.実行状態().休止しているか()));
        let 置き直し: usize = 細分ごと
            .iter()
            .map(|バッチ| {
                バッチ
                    .剛体どうしの接触拘束()
                    .iter()
                    .filter(|拘束| 拘束.静止摩擦の解の状態().錨を置き直したか())
                    .count()
            })
            .sum();
        let 滑走中: usize = 細分ごと
            .iter()
            .map(|バッチ| {
                バッチ
                    .剛体どうしの接触拘束()
                    .iter()
                    .filter(|拘束| 拘束.静止摩擦の解の状態().滑走中か())
                    .count()
            })
            .sum();
        let 食い込み = 細分ごと
            .iter()
            .flat_map(|バッチ| {
                バッチ
                    .剛体どうしの接触拘束()
                    .iter()
                    .map(|拘束| 拘束.引数().生成時の符号付き貫通量.長さ().値())
            })
            .fold(0.0_f32, f32::max);
        if (詳しく綴る刻み.0..=詳しく綴る刻み.1).contains(&刻み) || 刻み % 10 == 0 {
            println!(
                "{刻み} | {休止} | {置き直し} | {滑走中} | {食い込み:.3e} | {} | {:.3e} | {} | {:.3e}",
                対の接触点の数の分布(&細分ごと, 箱id一覧[0], 箱id一覧[1]),
                面の隔たり(&台帳, 箱id一覧[0], 箱id一覧[1]),
                対の接触点の数の分布(&細分ごと, 箱id一覧[1], 箱id一覧[2]),
                面の隔たり(&台帳, 箱id一覧[1], 箱id一覧[2])
            );
        }
    }
}

