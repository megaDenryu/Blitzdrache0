//! 箱10段の塔で、上下に積んだ箱の対の接触点集合が無い細分がどれだけあり、そのとき2つの箱の面がどれだけ離れているかを
//! 綴る計器(判断11・判断18。Issue #59の第3段階)。合否は判定しない。
//! 第1段と第2段の対について、刻みごとに、細分16本のうち接触点集合が無かった本数と、刻みの末の配置で測った面の隔たり
//! (上の箱の重心から下の箱の重心を引いた鉛直の差から箱の一辺1メートルを引いた長さ。正なら離れている)を綴る。
//! 接触点集合が無いのに隔たりが接触生成の余白より小さい正の値なら、2つの形が重なっていないために接触点集合が返らず、
//! 対が接触を失って別々の島になっている(判断11の「重なっていなければ接触点集合は返らない」の帰結)ことになる。
//! 隔たりは2つの重心の差の演算で測り、単精度の位置と二段の位置のどちらの配置でも同じ綴りで読める。
//! 実行は `cargo test -p blitz_sim --release 塔の上下の箱の隔たりと接触点集合の欠けを綴る -- --ignored --nocapture` である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11」「判断18」。

#![cfg(test)]

use super::tower_fixture::箱の塔の場面を作る;
use crate::contact::contact_batches::接触拘束の二つのバッチ;
use crate::rigid_body::{剛体の台帳, 剛体の識別子};

const 綴る刻みの数: usize = 600;
const 箱の一辺: f32 = 1.0;
const 綴り始める刻み: usize = 300;
const 綴る刻みの間隔: usize = 20;

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 塔の上下の箱の隔たりと接触点集合の欠けを綴る() {
    let (mut 工程, mut 台帳, 箱id一覧, _) = 箱の塔の場面を作る(10, false);
    let (下, 上) = (箱id一覧[0], 箱id一覧[1]);
    let mut 欠けた細分の合計 = 0_usize;
    let mut 正の隔たりの刻み = 0_usize;
    let mut 隔たりの最大 = f32::MIN;
    let mut 隔たりの最小 = f32::MAX;
    println!("刻み | 第1段と第2段の接触点集合が無い細分 | 刻みの末の面の隔たり(メートル。正なら離れている)");
    for 刻み in 0..綴る刻みの数 {
        let Ok(細分ごと) = 工程.一刻み進めて細分ごとのバッチを返す(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        let 欠けた = 細分ごと.iter().filter(|バッチ| 対の接触点の数(バッチ, 下, 上) == 0).count();
        欠けた細分の合計 += 欠けた;
        let 隔たり = 面の隔たり(&台帳, 下, 上);
        正の隔たりの刻み += usize::from(隔たり > 0.0);
        隔たりの最大 = 隔たりの最大.max(隔たり);
        隔たりの最小 = 隔たりの最小.min(隔たり);
        if 刻み >= 綴り始める刻み && 刻み % 綴る刻みの間隔 == 0 {
            println!("{刻み} | {欠けた} | {隔たり:.3e}");
        }
    }
    println!("接触点集合が無い細分の合計 {欠けた細分の合計} / {}", 綴る刻みの数 * 16);
    println!("刻みの末の隔たりが正の刻み {正の隔たりの刻み} / {綴る刻みの数}");
    println!("刻みの末の隔たりの最小 {隔たりの最小:.3e} 最大 {隔たりの最大:.3e}");
}

fn 対の接触点の数(バッチ: &接触拘束の二つのバッチ, 下: 剛体の識別子, 上: 剛体の識別子) -> usize {
    バッチ
        .剛体どうしの接触拘束()
        .iter()
        .filter(|拘束| (拘束.引数().剛体a, 拘束.引数().剛体b) == (下, 上))
        .count()
}

// 上の箱の重心から下の箱の重心を引いた鉛直の差から一辺を引く。重心の差の演算で測るため、配置の位置の型に依らない。
fn 面の隔たり(台帳: &剛体の台帳, 下: 剛体の識別子, 上: 剛体の識別子) -> f32 {
    let (Ok(下の剛体), Ok(上の剛体)) = (台帳.参照する(下), 台帳.参照する(上)) else {
        panic!("箱の参照に失敗した");
    };
    (上の剛体.配置().重心の位置() - 下の剛体.配置().重心の位置()).y().値() - 箱の一辺
}
