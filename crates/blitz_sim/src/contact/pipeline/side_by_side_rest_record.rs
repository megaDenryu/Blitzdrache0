//! 側面で接する2つの箱が別々の刻みで休止する後退を切り分ける計器(判断18。Issue #59の第3段階)。合否は判定しない。
//! 綴るのは刻みごとの、細分16本のうち剛体どうしの接触拘束(側面の接触)が在った本数・錨を置き直した拘束が在った本数・
//! 滑走中の拘束が在った本数と、刻みの末の箱ごとの運動の静穏と休止の有無である。側面の接触点集合が細分ごとに出たり
//! 消えたりして島が2つに割れているなら、剛体どうしの接触拘束が在る本数が16を下回る刻みが休止の手前に現れる。
//! 実行は `cargo test -p blitz_sim --release 側面で接する二つの箱の島の分割と静穏の四条件を綴る -- --ignored --nocapture` である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18」。

#![cfg(test)]

use super::side_by_side_fixture::側面で接する箱の列の場面を作る;
use crate::contact::contact_batches::接触拘束の二つのバッチ;

const 綴り始める刻み: usize = 690;
const 綴り終える刻み: usize = 745;

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 側面で接する二つの箱の島の分割と静穏の四条件を綴る() {
    let (mut 工程, mut 台帳, 箱一覧) = 側面で接する箱の列の場面を作る(2);
    println!("刻み | 側面の接触が在る細分 | 錨を置き直した細分 | 滑走中の細分 | 左: 静穏 休止 | 右: 静穏 休止");
    for 刻み in 0..=綴り終える刻み {
        let Ok(細分ごと) = 工程.一刻み進めて細分ごとのバッチを返す(&mut 台帳) else {
            panic!("刻み {刻み} で一刻み進めるエラー");
        };
        if 刻み < 綴り始める刻み {
            continue;
        }
        let 側面の接触 = 細分ごと.iter().filter(|バッチ| !バッチ.剛体どうしの接触拘束().is_empty()).count();
        let 置き直し = 細分ごと.iter().filter(|バッチ| 錨を置き直した拘束があるか(バッチ)).count();
        let 滑走 = 細分ごと.iter().filter(|バッチ| 滑走中の拘束があるか(バッチ)).count();
        let 欄: Vec<String> = 箱一覧
            .iter()
            .map(|&識別子| {
                let Ok(剛体) = 台帳.参照する(識別子) else {
                    panic!("箱の参照に失敗した: {識別子:?}");
                };
                format!("{} {}", 剛体.運動が静穏か(), 剛体.実行状態().休止しているか())
            })
            .collect();
        println!("{刻み} | {側面の接触} | {置き直し} | {滑走} | {}", 欄.join(" | "));
    }
}

fn 錨を置き直した拘束があるか(バッチ: &接触拘束の二つのバッチ) -> bool {
    バッチ
        .剛体どうしの接触拘束()
        .iter()
        .any(|拘束| 拘束.静止摩擦の解の状態().錨を置き直したか())
        || バッチ
            .剛体と静的世界の接触拘束()
            .iter()
            .any(|拘束| 拘束.静止摩擦の解の状態().錨を置き直したか())
}

fn 滑走中の拘束があるか(バッチ: &接触拘束の二つのバッチ) -> bool {
    バッチ.剛体どうしの接触拘束().iter().any(|拘束| 拘束.静止摩擦の解の状態().滑走中か())
        || バッチ.剛体と静的世界の接触拘束().iter().any(|拘束| 拘束.静止摩擦の解の状態().滑走中か())
}
