//! 剛体どうしの接触の生成が守る参加者の順の不変条件の試験(判断11・判断16)。積む工程が剛体aの識別子を剛体bの識別子より
//! 小さいことに強制することを、実際に参加者を反転させて確かめる。反転を許すと、履歴の鍵は識別子を昇順へ正規化して同じ値に
//! なる一方で、特徴の識別と局所点と接触法線は参加者の順のまま入るため、次の細分の併走が向きの違う錨をそのまま引き継ぐ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断16: 接触の履歴は参加者の組ごとに特徴の識別を鍵に全順序の併走で対応付け、暖機はしない」

#![allow(clippy::unwrap_used)]

use super::batch_builder::接触拘束のバッチの組み立て;
use super::contact_test_fixtures::{単一の材質の混合則, 台帳へ登録する, 接触に参加する剛体を作る, 試験の刻み幅};
use super::generation_error::接触拘束の生成エラー;
use super::stacked_box_fixture::{上の箱の配置, 上下の箱の接触点集合, 下の箱の配置};
use crate::rigid_body::{剛体の台帳, 姿勢};
use crate::xpbd::コンプライアンス;

#[test]
fn 参加者を反転させた接触点集合は昇順でないとして拒まれる() {
    let 混合則 = 単一の材質の混合則();
    let 接触点集合 = 上下の箱の接触点集合(姿勢::恒等());
    let (上の配置, 下の配置) = (上の箱の配置(姿勢::恒等()), 下の箱の配置());
    let mut 台帳 = 剛体の台帳::空();
    let 上 = 接触に参加する剛体を作る(台帳へ登録する(&mut 台帳, 上の配置), 上の配置);
    let 下 = 接触に参加する剛体を作る(台帳へ登録する(&mut 台帳, 下の配置), 下の配置);
    assert!(上.識別子() < 下.識別子(), "試験の材料の識別子が昇順でない");
    let mut 組み立て = 接触拘束のバッチの組み立て::生成する(&混合則, コンプライアンス::硬い(), 試験の刻み幅(), 1);
    assert_eq!(
        組み立て.剛体どうしの接触点集合を積む(&下, &上, &接触点集合),
        Err(接触拘束の生成エラー::剛体の識別子が昇順でない {
            第1の剛体の識別子: 下.識別子().値(),
            第2の剛体の識別子: 上.識別子().値(),
        })
    );
    assert!(組み立て.二つのバッチを組み立てる().剛体どうしの接触拘束().is_empty());
}
