//! 材質の識別子: 表面物性を引くための番号(判断15)。ゲーム固有の材質の名前(木・氷・ゴム)は `blitz_sim` へ持ち込まず、
//! 識別子は番号であり、番号から表面物性を引く表は混合則が持つ。
//! 全順序を持つのは、材質の対を昇順へ正規化して混合則を可換にするためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断15: 接触物性は両表面の物性から混合則で決め、既定則と材質対の上書き表を持つ」

/// 表面物性を引くための番号。衝突形状の子形状と静的世界の接触相手がこれを持つ。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[repr(transparent)]
pub struct 材質の識別子(u32);

impl 材質の識別子 {
    /// 番号から作る。どの番号も登録されうるため検査は無く、登録されていない番号は混合則の参照が型付きエラーで拒む。
    pub fn 生成する(番号: u32) -> Self {
        Self(番号)
    }

    /// エラーの文とGPUのバイト列へ写す境界向けの生値。
    pub fn 値(&self) -> u32 {
        self.0
    }
}
