//! 接触物性: 接触1つに対して混合則が決めた静止摩擦係数・動摩擦係数・反発係数の組(判断15)。
//! 表面物性と同じ3つの係数と同じ値域を持ちながら別の型にするのは、片方の表面の性質と、混ぜた後の接触の性質を
//! 取り違えても型が通る形を避けるためである。値域の検査は表面物性が1箇所で持ち、この型はそれを包む。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断15: 接触物性は両表面の物性から混合則で決め、既定則と材質対の上書き表を持つ」

use super::friction_coefficient::摩擦係数;
use super::property_error::接触物性エラー;
use super::restitution_coefficient::反発係数;
use super::surface_property::表面物性;

/// 接触1つが持つ摩擦と反発の3つの係数。混合則の既定則と材質対の上書き表だけがこれを作る。
#[derive(Debug, Clone, Copy, PartialEq)]
#[repr(transparent)]
pub struct 接触物性(表面物性);

impl 接触物性 {
    /// 材質対の上書き表へ登録する値を作る。検査は表面物性と同じである。
    pub fn 生成する(
        静止摩擦係数: 摩擦係数, 動摩擦係数: 摩擦係数, 反発係数: 反発係数
    ) -> Result<Self, 接触物性エラー> {
        Ok(Self(表面物性::生成する(静止摩擦係数, 動摩擦係数, 反発係数)?))
    }

    // 既定則の混合が作る係数。相乗平均と最大値が値域と 0 ≤ μ_d ≤ μ_s を保つため、検査を通し直さない入口を混合の側へ開く。
    pub(super) fn 検査済みの係数から組む(
        静止摩擦係数: 摩擦係数, 動摩擦係数: 摩擦係数, 反発係数: 反発係数
    ) -> Self {
        Self(表面物性::検査済みの係数から組む(静止摩擦係数, 動摩擦係数, 反発係数))
    }

    /// 滑り出す限界を決める摩擦係数。
    pub fn 静止摩擦係数(&self) -> 摩擦係数 {
        self.0.静止摩擦係数()
    }

    /// 滑走中の抵抗を決める摩擦係数。
    pub fn 動摩擦係数(&self) -> 摩擦係数 {
        self.0.動摩擦係数()
    }

    /// 跳ね返りの強さを決める反発係数。
    pub fn 反発係数(&self) -> 反発係数 {
        self.0.反発係数()
    }
}
