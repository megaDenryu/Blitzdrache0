//! 接触拘束の2つのバッチ(判断11)。剛体と剛体の接触拘束と、剛体と静的世界の接触拘束を、参加者の組ごとに分けて密に並べる。
//! 1つの型へ潰さないのは、静的世界(三角形・建物・高さ場)には剛体の識別子も重心局所点も無いためであり、
//! 参加する自由度の組ごとに別の密なバッチを持つ判断10の規則そのものである。
//! 接触点集合ごとの範囲を一緒に持つのは、静止摩擦のクーロン円錐の判定が接触点集合の単位だからである(判断13)。
//! 細分の開始で組み立て、細分の終了で捨てる。刻みを跨いで持つ口は無い。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use super::body_body_contact::剛体と剛体の接触拘束;
use super::body_static_contact::剛体と静的世界の接触拘束;
use super::manifold_range::接触点集合の占める範囲;

/// 1つの細分が解く接触拘束の全体。
#[derive(Debug, Clone, PartialEq)]
pub struct 接触拘束の二つのバッチ {
    剛体どうし: Vec<剛体と剛体の接触拘束>,
    剛体と静的世界: Vec<剛体と静的世界の接触拘束>,
    剛体どうしの接触点集合の範囲: Vec<接触点集合の占める範囲>,
    剛体と静的世界の接触点集合の範囲: Vec<接触点集合の占める範囲>,
}

impl 接触拘束の二つのバッチ {
    // 組み立てが積み終えた2つの一覧と、その接触点集合ごとの範囲を受ける唯一の入口。件数の上限と内容の検査は積む工程が済ませている。
    pub(super) fn 積み終えた一覧から組む(
        剛体どうし: Vec<剛体と剛体の接触拘束>,
        剛体と静的世界: Vec<剛体と静的世界の接触拘束>,
        剛体どうしの接触点集合の範囲: Vec<接触点集合の占める範囲>,
        剛体と静的世界の接触点集合の範囲: Vec<接触点集合の占める範囲>,
    ) -> Self {
        Self {
            剛体どうし,
            剛体と静的世界,
            剛体どうしの接触点集合の範囲,
            剛体と静的世界の接触点集合の範囲,
        }
    }

    /// 2つのバッチを接触の履歴の鍵の昇順へ並べ替える。判断16の併走は2つの昇順の一覧だけを受け、
    /// 判断17の反復の順序も同じ昇順であるため、細分は接触点集合を積み終えた直後にこれを1度呼ぶ。
    /// 並べ替えるのは接触点集合の範囲の中だけであり、範囲どうしの順は積んだ順のままである。
    /// 注意: 全体が昇順になるのは、候補の列挙が参加者の組を昇順に積むことに依る。破れた場合は
    /// 判断16の併走が `接触の履歴エラー::鍵の一覧が昇順でない` で落ちる(その検査がこの前提の機械の強制である)。
    /// 鍵は接触点ごとに相異なるため、安定でない並べ替えでも結果は入力だけで決まる。
    pub fn 鍵の昇順へ並べ替える(&mut self) {
        for 番号 in 0..self.剛体どうしの接触点集合の範囲.len() {
            let 範囲 = self.剛体どうしの接触点集合の範囲[番号];
            self.剛体どうし[範囲.開始の添字()..範囲.終わりの添字()].sort_unstable_by_key(剛体と剛体の接触拘束::履歴の鍵);
        }
        for 番号 in 0..self.剛体と静的世界の接触点集合の範囲.len() {
            let 範囲 = self.剛体と静的世界の接触点集合の範囲[番号];
            self.剛体と静的世界[範囲.開始の添字()..範囲.終わりの添字()].sort_unstable_by_key(剛体と静的世界の接触拘束::履歴の鍵);
        }
    }

    /// 剛体と剛体の接触拘束の一覧。並びは積んだ順である。
    pub fn 剛体どうしの接触拘束(&self) -> &[剛体と剛体の接触拘束] {
        &self.剛体どうし
    }

    /// 剛体と静的世界の接触拘束の一覧。並びは積んだ順である。
    pub fn 剛体と静的世界の接触拘束(&self) -> &[剛体と静的世界の接触拘束] {
        &self.剛体と静的世界
    }

    /// 反復が乗数を更新するために借りる、剛体と剛体の接触拘束の一覧。
    pub fn 剛体どうしの接触拘束を反復のために借りる(&mut self) -> &mut [剛体と剛体の接触拘束] {
        &mut self.剛体どうし
    }

    /// 反復が乗数を更新するために借りる、剛体と静的世界の接触拘束の一覧。
    pub fn 剛体と静的世界の接触拘束を反復のために借りる(&mut self) -> &mut [剛体と静的世界の接触拘束] {
        &mut self.剛体と静的世界
    }

    /// このバッチに載っている剛体と剛体の接触点集合の数。法線の同時解法と静止摩擦はこの単位で解く。
    pub fn 剛体どうしの接触点集合の数(&self) -> usize {
        self.剛体どうしの接触点集合の範囲.len()
    }

    /// このバッチに載っている剛体と静的世界の接触点集合の数。
    pub fn 剛体と静的世界の接触点集合の数(&self) -> usize {
        self.剛体と静的世界の接触点集合の範囲.len()
    }

    /// 反復が接触点集合1つぶんの拘束をまとめて借りる。番号は0から接触点集合の数の手前までである。
    /// 法線の同時解法と静止摩擦のクーロン円錐は、どちらもこの単位で解く。
    pub fn 剛体どうしの接触点集合を反復のために借りる(
        &mut self, 集合の番号: usize
    ) -> &mut [剛体と剛体の接触拘束] {
        let 範囲 = self.剛体どうしの接触点集合の範囲[集合の番号];
        &mut self.剛体どうし[範囲.開始の添字()..範囲.終わりの添字()]
    }

    /// 反復が接触点集合1つぶんの拘束をまとめて借りる。番号は0から接触点集合の数の手前までである。
    /// 法線の同時解法と静止摩擦のクーロン円錐は、どちらもこの単位で解く。
    pub fn 剛体と静的世界の接触点集合を反復のために借りる(
        &mut self,
        集合の番号: usize,
    ) -> &mut [剛体と静的世界の接触拘束] {
        let 範囲 = self.剛体と静的世界の接触点集合の範囲[集合の番号];
        &mut self.剛体と静的世界[範囲.開始の添字()..範囲.終わりの添字()]
    }
}
