//! 接触拘束の2つのバッチ(判断11)。剛体と剛体の接触拘束と、剛体と静的世界の接触拘束を、参加者の組ごとに分けて密に並べる。
//! 1つの型へ潰さないのは、静的世界(三角形・建物・高さ場)には剛体の識別子も重心局所点も無いためであり、
//! 参加する自由度の組ごとに別の密なバッチを持つ判断10の規則そのものである。
//! 細分の開始で組み立て、細分の終了で捨てる。刻みを跨いで持つ口は無い。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use super::body_body_contact::剛体と剛体の接触拘束;
use super::body_static_contact::剛体と静的世界の接触拘束;

/// 1つの細分が解く接触拘束の全体。
#[derive(Debug, Clone, PartialEq)]
pub struct 接触拘束の二つのバッチ {
    剛体どうし: Vec<剛体と剛体の接触拘束>,
    剛体と静的世界: Vec<剛体と静的世界の接触拘束>,
}

impl 接触拘束の二つのバッチ {
    // 組み立てが積み終えた2つの一覧を受ける唯一の入口。件数の上限と内容の検査は積む工程が済ませている。
    pub(super) fn 積み終えた一覧から組む(
        剛体どうし: Vec<剛体と剛体の接触拘束>, 剛体と静的世界: Vec<剛体と静的世界の接触拘束>
    ) -> Self {
        Self {
            剛体どうし, 剛体と静的世界
        }
    }

    /// 剛体と剛体の接触拘束の一覧。並びは積んだ順である。
    pub fn 剛体どうし(&self) -> &[剛体と剛体の接触拘束] {
        &self.剛体どうし
    }

    /// 剛体と静的世界の接触拘束の一覧。並びは積んだ順である。
    pub fn 剛体と静的世界(&self) -> &[剛体と静的世界の接触拘束] {
        &self.剛体と静的世界
    }

    /// 反復が乗数を更新するために借りる、剛体と剛体の接触拘束の一覧。
    pub fn 剛体どうしを反復のために借りる(&mut self) -> &mut [剛体と剛体の接触拘束] {
        &mut self.剛体どうし
    }

    /// 反復が乗数を更新するために借りる、剛体と静的世界の接触拘束の一覧。
    pub fn 剛体と静的世界を反復のために借りる(&mut self) -> &mut [剛体と静的世界の接触拘束] {
        &mut self.剛体と静的世界
    }
}
