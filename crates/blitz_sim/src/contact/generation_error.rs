//! 接触拘束の生成が拒んだ入力(判断11・判断12)。倍精度で返る接触点集合を単精度へ狭める境界の失敗と、
//! 参加者の組み合わせの誤りと、接触物性を決められない材質と、衝突の問い合わせの基準原点に相対な形を組めない入力の4つを述べる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use blitz_collision::shape::直方体の生成エラー;
use blitz_math::{クォータニオンエラー, 二段の位置エラー, 単位変換エラー, 方向エラー};
use thiserror::Error;

use super::property_error::接触物性エラー;
use crate::xpbd::コンプライアンスエラー;

/// 接触点集合から接触拘束のバッチを作る工程が拒んだ入力。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 接触拘束の生成エラー {
    /// 接触点の位置を倍精度から単精度へ狭められない。
    #[error("接触点の位置を単精度へ狭められない: {0}")]
    接触点の位置を狭められない(単位変換エラー),
    /// 接触点の符号付き貫通量を倍精度から単精度へ狭められない。
    #[error("接触点の符号付き貫通量を単精度へ狭められない: {0}")]
    符号付き貫通量を狭められない(単位変換エラー),
    /// 接触点集合が共有する単位法線を、ワールドの単位方向として作り直せない。
    #[error("接触法線をワールドの単位方向へ写せない: {0}")]
    接触法線をワールドへ写せない(#[from] 方向エラー),
    /// 形の最小の厚みが正の有限値でない。深い初期重なりの切り詰めの上限が定まらない。
    #[error("形の最小の厚みは正の有限値でなければならない(指定値: {値})")]
    形の最小の厚みが値域の外 { 値: f32 },
    /// 同じ剛体の識別子どうしで接触拘束を作ろうとした。
    #[error("同じ剛体どうしの接触拘束は作れない(剛体の識別子: {剛体の識別子})")]
    同じ剛体どうしの接触 { 剛体の識別子: u32 },
    /// 2つの剛体の識別子が昇順でない。逆順で積むと同じ鍵に向きの違う特徴と錨と法線が結びつく(判断16)。
    #[error("剛体どうしの接触は識別子の昇順で積まなければならない(第1: {第1の剛体の識別子}、第2: {第2の剛体の識別子})")]
    剛体の識別子が昇順でない {
        第1の剛体の識別子: u32, 第2の剛体の識別子: u32
    },
    /// 2つの剛体が別の基準原点で形を組んでいる。同じ問い合わせの2つの形は同じ原点に相対でなければならない(判断3)。
    #[error("剛体どうしの接触は同じ基準原点で形を組まなければならない(第1: {第1の剛体の識別子}、第2: {第2の剛体の識別子})")]
    二つの剛体の基準原点が違う {
        第1の剛体の識別子: u32, 第2の剛体の識別子: u32
    },
    /// 基準原点に相対な直方体を組めない(中心が有限でないか座標の上限を越えている)。
    #[error("基準原点に相対な直方体を組めない: {0}")]
    相対な直方体を組めない(#[from] 直方体の生成エラー),
    /// 剛体の姿勢を形の回転へ写せない。
    #[error("剛体の姿勢を形の回転へ写せない: {0}")]
    姿勢を形の回転へ写せない(#[from] クォータニオンエラー),
    /// 基準原点からの相対の点を二段の位置へ戻せない。
    #[error("基準原点からの相対の点を二段の位置へ戻せない: {0}")]
    基準原点からの二段の位置を組めない(#[from] 二段の位置エラー),
    /// 接触物性を決められない。材質の表面物性が登録されていない場合がこれである。
    #[error("接触物性を決められない: {0}")]
    接触物性を決められない(#[from] 接触物性エラー),
    /// 接触のコンプライアンスの刻み依存量を導けない。
    #[error("接触のコンプライアンスを刻み幅で解けない: {0}")]
    刻み依存量を導けない(#[from] コンプライアンスエラー),
}
