//! 接触点集合1つをバッチへ積む工程(判断11)。担当するのは、接触点集合が返した全部の点を1点へ潰さずに拘束へ写すことと、
//! 共有の座標系の点を各参加者の座標へ写すことと、両参加者の材質から接触物性を決めることの3つである。
//! 組み立ての型の定義と受け皿の確保から分けているのは、確保が細分の開始で1度だけ起こるのに対し、この工程が候補の対の
//! 数だけ呼ばれるためである。
//! 接触法線は接触点集合が1つだけ持ち、第1の形から第2の形へ向かう。第1の形が剛体a、第2の形が剛体bまたは静的世界である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use blitz_collision::contact_set::接触点集合;

use super::batch_builder::接触拘束のバッチの組み立て;
use super::body_body_contact::剛体と剛体の接触拘束;
use super::body_body_contact_parameters::剛体と剛体の接触拘束の引数;
use super::body_static_contact::剛体と静的世界の接触拘束;
use super::body_static_contact_parameters::剛体と静的世界の接触拘束の引数;
use super::contacting_body::接触に参加する剛体;
use super::feature_identity::接触の特徴の識別;
use super::generation_error::接触拘束の生成エラー;
use super::non_penetration::非貫通の解き方;
use super::shared_frame::{接触法線をワールドへ写す, 貫通量を単精度へ狭める};
use super::static_world_partner::静的世界の接触相手;

impl 接触拘束のバッチの組み立て<'_> {
    /// 2つの剛体の接触点集合を剛体と剛体のバッチへ積む。全部の接触点が1件ずつ拘束になる。
    pub fn 剛体どうしの接触点集合を積む<特徴: Copy + Into<接触の特徴の識別>>(
        &mut self,
        剛体a: &接触に参加する剛体,
        剛体b: &接触に参加する剛体,
        接触点集合: &接触点集合<特徴>,
    ) -> Result<(), 接触拘束の生成エラー> {
        if 剛体a.識別子() == 剛体b.識別子() {
            return Err(接触拘束の生成エラー::同じ剛体どうしの接触 {
                剛体の識別子: 剛体a.識別子().値(),
            });
        }
        let 接触法線 = 接触法線をワールドへ写す(接触点集合.共有の単位法線())?;
        let 接触物性 = self.混合則().接触物性を求める(剛体a.材質(), 剛体b.材質())?;
        let 解き方 = 非貫通の解き方::生成する(self.接触のコンプライアンス(), 剛体a.形の最小の厚み().薄い方を選ぶ(剛体b.形の最小の厚み()));
        let 接触点集合の開始の添字 = self.剛体どうしの積んだ接触点の数();
        for 接触点 in 接触点集合.接触点を順に並べる() {
            let 引数 = 剛体と剛体の接触拘束の引数 {
                剛体a: 剛体a.識別子(),
                剛体b: 剛体b.識別子(),
                局所接触点a: 剛体a.接触点を重心局所へ写す(接触点.第1の形の上の位置())?,
                局所接触点b: 剛体b.接触点を重心局所へ写す(接触点.第2の形の上の位置())?,
                接触法線,
                生成時の貫通量: 貫通量を単精度へ狭める(接触点.貫通量())?,
                特徴の識別: (*接触点.特徴の識別()).into(),
                接触物性,
                解き方,
            };
            self.剛体どうしへ積む(剛体と剛体の接触拘束::引数と刻み幅から生成する(引数, self.刻み幅())?);
        }
        self.剛体どうしの接触点集合の範囲を閉じる(接触点集合の開始の添字);
        Ok(())
    }

    /// 剛体と静的世界の接触相手の接触点集合を剛体と静的世界のバッチへ積む。静的世界の側の点は世界位置のまま持つ。
    pub fn 剛体と静的世界の接触点集合を積む<特徴: Copy + Into<接触の特徴の識別>>(
        &mut self,
        剛体: &接触に参加する剛体,
        相手: &静的世界の接触相手,
        接触点集合: &接触点集合<特徴>,
    ) -> Result<(), 接触拘束の生成エラー> {
        let 接触法線 = 接触法線をワールドへ写す(接触点集合.共有の単位法線())?;
        let 接触物性 = self.混合則().接触物性を求める(剛体.材質(), 相手.材質())?;
        let 解き方 = 非貫通の解き方::生成する(self.接触のコンプライアンス(), 剛体.形の最小の厚み().薄い方を選ぶ(相手.形の最小の厚み()));
        let 接触点集合の開始の添字 = self.剛体と静的世界の積んだ接触点の数();
        for 接触点 in 接触点集合.接触点を順に並べる() {
            let 引数 = 剛体と静的世界の接触拘束の引数 {
                剛体: 剛体.識別子(),
                静的世界の接触相手: 相手.識別子(),
                剛体側の局所接触点: 剛体.接触点を重心局所へ写す(接触点.第1の形の上の位置())?,
                静的世界側の接触点: 相手.接触点の世界位置を求める(接触点.第2の形の上の位置())?,
                接触法線,
                生成時の貫通量: 貫通量を単精度へ狭める(接触点.貫通量())?,
                特徴の識別: (*接触点.特徴の識別()).into(),
                接触物性,
                解き方,
            };
            self.剛体と静的世界へ積む(剛体と静的世界の接触拘束::引数と刻み幅から生成する(
                引数,
                self.刻み幅(),
            )?);
        }
        self.剛体と静的世界の接触点集合の範囲を閉じる(接触点集合の開始の添字);
        Ok(())
    }
}
