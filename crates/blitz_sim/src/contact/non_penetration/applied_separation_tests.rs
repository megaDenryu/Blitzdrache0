//! 射影が返した補正を実際に配置へ適用して測る、法線方向の分離の増分の検査(判断12)。担当するのは、1細分に詰めてよい
//! 長さの上限が、線形化した補正の長さだけでなく、補正を適用した後の接触点の実際の移動に対しても効くことを固定することである。
//! 姿勢の補正は正規化した有限回転として適用されるため、腕の先が描く弦は1次の接線の変位と向きが違い、法線への射影は
//! 1次の値を上回りうる。上限は形の最小の厚み1回分であり無条件に無視できる大きさではないため、線形の帳簿を見る
//! `non_penetration_correction_tests` とは別に、ここでは配置へ適用した後の世界座標から増分を測り直す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::applied_separation_fixture::{局所接触点と解き方を持つ拘束, 補正を配置へ適用して追う剛体};
use super::fixture::{解き方を作る, 試験の形の最小の厚み};
use super::result::非貫通の一回の射影の結果;

const 測る反復の回数: usize = 8;

#[test]
fn 補正を配置へ適用して測った分離の増分の累計は形の最小の厚みを超えない() {
    let mut 剛体 = 補正を配置へ適用して追う剛体::偏心した接触点と異方の主慣性で生成する();
    let mut 拘束 = 局所接触点と解き方を持つ拘束(剛体.局所接触点(), 解き方を作る(0.0));
    let 静的世界の点 = 拘束.引数().静的世界側の接触点;
    let 最初の一般化逆質量 = 剛体.接触点の一般化逆質量();
    let mut 正の分離の増分の累計 = メートル::生成する(0.0);
    for _ in 0..測る反復の回数 {
        let 前の隔たり = 剛体.静的世界の点からの隔たり(静的世界の点);
        let 結果 = 拘束.一回射影する(&剛体.参加者());
        let 非貫通の一回の射影の結果::補正した { 補正a, .. } = 結果 else {
            panic!("深く貫通しているのに補正しなかった: {結果:?}");
        };
        剛体.補正を配置へ適用する(補正a);
        let 増分 = 剛体.静的世界の点からの隔たり(静的世界の点) - 前の隔たり;
        if 増分.値() > 0.0 {
            正の分離の増分の累計 = 正の分離の増分の累計 + 増分;
        }
    }
    let 有効逆質量の変化 = (剛体.接触点の一般化逆質量().値() - 最初の一般化逆質量.値()).abs();
    assert!(有効逆質量の変化 > 0.1, "反復のあいだに有効逆質量が変わっていない材料では反証にならない");
    assert!(
        正の分離の増分の累計.値() <= 試験の形の最小の厚み,
        "実測の分離の増分の累計{}メートルが形の最小の厚み{試験の形の最小の厚み}メートルを超えた",
        正の分離の増分の累計.値()
    );
}
