//! 接触点集合の法線を同時に解く連立の1行(判断12)。接触点1つが持つ2つの参加点・接触法線・解の状態・一刻みの係数を
//! 束ね、連立が要る量(隔たり・交差の有効逆質量・乗数の上限)と、求めた増分から作る補正をこの型のメソッドで返す。
//! 拘束の型から分けているのは、剛体と剛体の接触拘束と剛体と静的世界の接触拘束が同じ連立へ入るためである。
//! 交差の有効逆質量が要るのは、点ごとに順に解くと1点の補正が次の点の腕と有効逆質量を変え、面と面の接触で
//! 剛体が点の間を往復するためである。行どうしの結び付きを行列に持てば、集合の全部の点を1度に解ける。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

use blitz_math::{メートル, ワールド, 方向, 符号付き逆キログラム, 逆キログラム};

use super::super::contact_projection_participant::接触の射影に参加する点;
use super::coefficients::非貫通の一刻みの係数;
use super::substep_state::非貫通の一細分の解の状態;
use crate::rigid_xpbd::姿勢自由度の補正;
use crate::xpbd::ラグランジュ乗数;

/// 接触点集合の法線の連立の1行。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 非貫通の接触点集合の一行 {
    第1の参加点: 接触の射影に参加する点,
    第2の参加点: 接触の射影に参加する点,
    接触法線: 方向<ワールド>,
    解の状態: 非貫通の一細分の解の状態,
    一刻みの係数: 非貫通の一刻みの係数,
}

impl 非貫通の接触点集合の一行 {
    /// 接触拘束がこの反復の参加点と自分の解の状態から作る。接触法線は第1の参加者から第2の参加者へ向かう向きである。
    pub fn 生成する(
        第1の参加点: 接触の射影に参加する点,
        第2の参加点: 接触の射影に参加する点,
        接触法線: 方向<ワールド>,
        解の状態: 非貫通の一細分の解の状態,
        一刻みの係数: 非貫通の一刻みの係数,
    ) -> Self {
        Self {
            第1の参加点,
            第2の参加点,
            接触法線,
            解の状態,
            一刻みの係数,
        }
    }

    /// いまの配置での法線方向の隔たり d = (p_2 − p_1)·n。負が貫通である。
    pub fn 隔たり(&self) -> メートル {
        (self.第2の参加点.世界位置() - self.第1の参加点.世界位置()).方向に沿う長さ(self.接触法線)
    }

    /// 補正で閉じられる隔たり。隔たりの大きさが世界位置の表現の刻みを下回るときは零である。
    /// その隔たりは補正を積んでも配置が1ビットも動かず閉じられないため、満たされた行として扱う。
    /// 零に落とさないと、動かない隔たりに対して毎反復が同じ増分を積み、法線の乗数の合計が反復回数に比例して増える。
    pub fn 補正で閉じられる隔たり(&self) -> メートル {
        if self.隔たりが表現の刻みの内側か() {
            メートル::生成する(0.0)
        } else {
            self.隔たり()
        }
    }

    /// いまの配置の上でこの行の隔たりが表現の刻みを下回るか。有効集合の出し入れもこの判定を読む。
    pub fn 隔たりが表現の刻みの内側か(&self) -> bool {
        let 刻み = self.隔たりの表現の刻み();
        self.隔たり() < 刻み && self.隔たり() > 刻み * -1.0
    }

    /// この行の隔たりが持つ表現の刻み Σ_k |n_k| (ulp(p_1,k) + ulp(p_2,k))。
    pub fn 隔たりの表現の刻み(&self) -> メートル {
        self.第1の参加点
            .二つの点の世界位置の差を向きへ射影した丸めの大きさ(&self.第2の参加点, self.接触法線)
    }

    /// この細分でこの行が積んだ法線のラグランジュ乗数。
    pub fn 法線のラグランジュ乗数(&self) -> ラグランジュ乗数 {
        self.解の状態.法線のラグランジュ乗数()
    }

    /// コンプライアンスの刻み依存量 α̃。連立の対角へ足す正則化である。
    pub fn 刻み依存量(&self) -> 逆キログラム {
        self.一刻みの係数.刻み依存量()
    }

    /// どちらの参加者も動かせない行か。この行は連立から外す。
    pub fn 動かせない組か(&self) -> bool {
        self.第1の参加点.動かせないか() && self.第2の参加点.動かせないか()
    }

    /// この行と相手の行が2つの参加者を通して結び付く有効逆質量 W_ij。同じ行を2度渡せば対角の成分になる。
    pub fn 有効逆質量の交差の寄与(&self, 相手: &Self) -> 符号付き逆キログラム {
        self.第1の参加点
            .二つの点の一般化逆質量の交差の寄与(self.接触法線, &相手.第1の参加点, 相手.接触法線)
            + self
                .第2の参加点
                .二つの点の一般化逆質量の交差の寄与(self.接触法線, &相手.第2の参加点, 相手.接触法線)
    }

    /// この細分でこの行が積んでよい乗数の上限。残りの相対補正の長さを有効逆質量の上界で乗数へ換算した値である。
    /// 前提: 動かせない組でない行にだけ呼ぶ(上界が0の行は換算が定まらない)。
    pub fn 乗数の上限(&self) -> ラグランジュ乗数 {
        self.法線のラグランジュ乗数()
            + ラグランジュ乗数::長さを逆質量で割って生成する(
                self.解の状態.残りの相対補正の長さ(self.一刻みの係数.一細分の補正の長さの上限()),
                self.有効逆質量の上界(),
            )
    }

    /// 乗数の増分を第1の参加者の補正へ分配する。呼び出し側は集合の全部の行の補正を合計してから1度だけ適用する。
    pub fn 乗数の増分を第1の参加者の補正へ分配する(&self, 乗数の増分: ラグランジュ乗数) -> 姿勢自由度の補正 {
        self.第1の参加点.乗数を補正へ分配する(self.接触法線.逆を向く方向(), 乗数の増分)
    }

    /// 乗数の増分を第2の参加者の補正へ分配する。静的世界の接触相手は動かせないため零の補正が返る。
    pub fn 乗数の増分を第2の参加者の補正へ分配する(&self, 乗数の増分: ラグランジュ乗数) -> 姿勢自由度の補正 {
        self.第2の参加点.乗数を補正へ分配する(self.接触法線, 乗数の増分)
    }

    /// 乗数の増分を足した後の解の状態。詰めた長さの累計も同じ換算で進む。
    pub fn 乗数の増分を足した解の状態(&self, 乗数の増分: ラグランジュ乗数) -> 非貫通の一細分の解の状態 {
        self.解の状態.乗数の増分を足した状態(乗数の増分, self.有効逆質量の上界())
    }

    // 補正を有限回転として適用したとき、乗数の増分1あたりに2つの参加点が法線方向へ実際に離れる長さの上界。
    fn 有効逆質量の上界(&self) -> 逆キログラム {
        self.第1の参加点.一般化逆質量の上界(self.接触法線) + self.第2の参加点.一般化逆質量の上界(self.接触法線)
    }
}
