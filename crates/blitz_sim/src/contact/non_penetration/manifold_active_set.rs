//! 接触点集合の法線の有効集合(判断12)。片側拘束の連立を解くとき、いま押し戻している行の集合をこの型が持つ。
//! 開始の集合を「貫通しているか、この細分で既に乗数を積んだ行」にするのは、片側拘束の有効集合の定義そのものである。
//! 動かせない組の行を最初から外すのは、その行が連立の対角に零を置き、解けない部分集合を作るためである。
//! 組み替えの順は行の番号の昇順で決め、同じ値が並んだときは小さい番号を採る(2回実行のビット一致のため)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

use blitz_collision::contact_set::接触点の上限;
use blitz_math::メートル;

use super::manifold_row::非貫通の接触点集合の一行;
use crate::xpbd::ラグランジュ乗数;

/// 接触点集合1つの中で、いま法線の反力を持たせている行の集合。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 法線の有効集合 {
    有効か: [bool; 接触点の上限],
}

impl 法線の有効集合 {
    /// 貫通している行と、この細分で既に乗数を積んだ行を有効にした開始の集合。
    /// 注意: 行の数が接触点の上限を超える集合は衝突数学層の不変条件の破れであり、添字の範囲外として落ちる。
    pub fn 貫通と乗数から始める(行: &[非貫通の接触点集合の一行]) -> Self {
        let mut 有効か = [false; 接触点の上限];
        for (番号, 一行) in 行.iter().enumerate() {
            let 貫通している = 一行.補正で閉じられる隔たり() < メートル::生成する(0.0);
            let 押し戻している = 貫通している || 一行.法線のラグランジュ乗数() > ラグランジュ乗数::零();
            有効か[番号] = 押し戻している && !一行.動かせない組か();
        }
        Self { 有効か }
    }

    pub fn 有効か(&self, 番号: usize) -> bool {
        self.有効か[番号]
    }

    /// 乗数が負に振れた行を有効集合から外す。
    pub fn 外す(&mut self, 番号: usize) {
        self.有効か[番号] = false;
    }

    /// 侵入が残った行を有効集合へ入れる。
    pub fn 入れる(&mut self, 番号: usize) {
        self.有効か[番号] = true;
    }
}
