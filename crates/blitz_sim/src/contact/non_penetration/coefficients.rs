//! 非貫通を解く条件と、それを刻み幅で解いた一細分の係数(判断12)。条件は接触の柔らかさと、1細分で詰めてよい貫通の
//! 長さの上限の2つである。上限は触れ合う2つの形のうち薄い方の厚みであり、深い初期重なりを数細分に分けて回復させる。
//! コンプライアンスの刻み依存量 α̃ = α ÷ h² は細分の開始で1度だけ導き、その細分の全反復で同じ値を使う。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

use blitz_math::逆キログラム;

use super::super::minimum_thickness::形の最小の厚み;
use crate::xpbd::{コンプライアンス, コンプライアンスエラー, 刻み幅};

/// 接触1点の非貫通を解く条件。コンプライアンス0が硬い接触であり、正の値は柔らかい接触である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 非貫通の解き方 {
    コンプライアンス: コンプライアンス,
    一細分の補正の長さの上限: 形の最小の厚み,
}

impl 非貫通の解き方 {
    /// 柔らかさと上限から作る。どちらも型が値域を守るため検査は無い。
    pub fn 生成する(コンプライアンス: コンプライアンス, 一細分の補正の長さの上限: 形の最小の厚み) -> Self {
        Self {
            コンプライアンス,
            一細分の補正の長さの上限,
        }
    }

    /// 細分1本の刻み幅で刻み依存量を導く。単精度の表現範囲を超える組み合わせは型付きエラーで拒む。
    pub fn 刻み幅で解く係数を導く(
        &self, 刻み幅: 刻み幅
    ) -> Result<非貫通の一刻みの係数, コンプライアンスエラー> {
        Ok(非貫通の一刻みの係数 {
            刻み依存量: self.コンプライアンス.刻み依存量(刻み幅)?,
            一細分の補正の長さの上限: self.一細分の補正の長さの上限,
        })
    }
}

/// 非貫通の射影が1細分の全反復で使う係数。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 非貫通の一刻みの係数 {
    刻み依存量: 逆キログラム,
    一細分の補正の長さの上限: 形の最小の厚み,
}

impl 非貫通の一刻みの係数 {
    pub(super) fn 刻み依存量(&self) -> 逆キログラム {
        self.刻み依存量
    }

    pub(super) fn 一細分の補正の長さの上限(&self) -> 形の最小の厚み {
        self.一細分の補正の長さの上限
    }
}
