//! 乗数の増分が負へ振れても、その細分で詰めた長さの予算が戻らないことの検査(判断12)。担当するのは、柔らかい接触で
//! 乗数の増分が正と負を行き来する状況を作り、射影が返した補正を配置へ適用して測った正の分離の増分の累計が
//! 形の最小の厚みを超えないことを固定することである。
//! 上界 U が保証するのは |実際の移動| ≤ U|Δλ| だけであり、Δλ が負のときに 実際の移動 ≤ U Δλ は成り立たない。
//! したがって、負の増分に上界を符号のまま掛けて使用済みの長さを減らすと、その後の正の増分との合計が厚みを超えうる。
//! 同じ細分の中では他の拘束も同じ剛体を動かすため、この接触点の隔たりは反復のあいだに深くも浅くも変わる。試験はその
//! 動かし方を最悪の側へ選び、深い隔たりと浅い隔たりを交互に与える。深い隔たりでは乗数の増分が正になり、浅い隔たりでは
//! 積み上がった α̃λ の項が上回って負になる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::applied_separation_fixture::{局所接触点と解き方を持つ拘束, 補正を配置へ適用して追う剛体};
use super::fixture::{解き方を作る, 試験の形の最小の厚み};
use super::result::非貫通の一回の射影の結果;
use crate::xpbd::ラグランジュ乗数;

const 柔らかい接触のコンプライアンス: f32 = 5.0e-4; // 刻み依存量 α̃ が有効逆質量の30倍ほどになり、乗数の増分が負へ振れる柔らかさ
const 深い隔たりのメートル: f32 = -12.0;
const 浅い隔たりのメートル: f32 = -0.05; // 離れている枝へ落ちない範囲で最も浅い隔たり
const 深い隔たりと浅い隔たりを往復する回数: usize = 8;

/// 1回の射影で乗数の増分が向いた側。
#[derive(Debug, Clone, Copy, PartialEq)]
enum 乗数の増分の符号 {
    正,
    零,
    負,
}

impl 乗数の増分の符号 {
    fn 増分から求める(増分: ラグランジュ乗数) -> Self {
        if 増分 > ラグランジュ乗数::零() {
            return Self::正;
        }
        if 増分 < ラグランジュ乗数::零() {
            Self::負
        } else {
            Self::零
        }
    }
}

// 他の拘束が与える隔たりの並び。深いところと浅いところを交互に往復する。
fn 深い隔たりと浅い隔たりの往復() -> impl Iterator<Item = メートル> {
    (0..深い隔たりと浅い隔たりを往復する回数).flat_map(|_| [メートル::生成する(深い隔たりのメートル), メートル::生成する(浅い隔たりのメートル)])
}

#[test]
fn 乗数の増分が負へ振れても正の分離の増分の累計は形の最小の厚みを超えない() {
    let mut 剛体 = 補正を配置へ適用して追う剛体::偏心した接触点と異方の主慣性で生成する();
    let mut 拘束 = 局所接触点と解き方を持つ拘束(剛体.局所接触点(), 解き方を作る(柔らかい接触のコンプライアンス));
    let 静的世界の点 = 拘束.引数().静的世界側の接触点;
    let mut 正の分離の増分の累計 = メートル::生成する(0.0);
    let mut 乗数の増分の符号の並び = Vec::new();
    for 目標の隔たり in 深い隔たりと浅い隔たりの往復() {
        剛体.他の拘束が隔たりを目標へ動かす(静的世界の点, 目標の隔たり);
        let 前の隔たり = 剛体.静的世界の点からの隔たり(静的世界の点);
        let 前の乗数 = 拘束.法線のラグランジュ乗数();
        let 結果 = 拘束.一回射影する(&剛体.参加者());
        let 非貫通の一回の射影の結果::補正した { 補正a, .. } = 結果 else {
            panic!("貫通しているのに補正しなかった: {結果:?}");
        };
        剛体.補正を配置へ適用する(補正a);
        let 増分 = 剛体.静的世界の点からの隔たり(静的世界の点) - 前の隔たり;
        if 増分.値() > 0.0 {
            正の分離の増分の累計 = 正の分離の増分の累計 + 増分;
        }
        乗数の増分の符号の並び.push(乗数の増分の符号::増分から求める(拘束.法線のラグランジュ乗数() - 前の乗数));
    }
    let 正負正 = [乗数の増分の符号::正, 乗数の増分の符号::負, 乗数の増分の符号::正];
    assert!(
        乗数の増分の符号の並び.windows(3).any(|三つ組| 三つ組 == 正負正),
        "乗数の増分が正・負・正の順に出ていない材料では反証にならない: {乗数の増分の符号の並び:?}"
    );
    assert!(
        正の分離の増分の累計.値() <= 試験の形の最小の厚み,
        "実測の正の分離の増分の累計{}メートルが形の最小の厚み{試験の形の最小の厚み}メートルを超えた",
        正の分離の増分の累計.値()
    );
}
