//! 接触点集合の法線を同時に解く工程の検査(判断12)。担当するのは3つを固定することである。
//! 接触点が1つだけの集合では逐次の射影と同じ乗数の増分になること、面と面の4点の特異な連立でも全部の点へ
//! 法線の乗数が載ること(一部の点だけに荷重が偏ると、判断14の速度段階が残りの点を接触していない点として外す)、
//! 求めた増分を配置へ1度だけ適用すると全部の接触点の食い込みが解けることである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ローカル, 変位};

use super::super::body_static_contact::剛体と静的世界の接触拘束;
use super::super::body_static_contact_parameters::剛体と静的世界の接触拘束の引数;
use super::super::contact_test_fixtures::{世界の位置を作る, 局所の変位を作る, 試験の刻み幅, 質量特性を作る};
use super::fixture::{剛体と静的世界の基本の引数, 高さの参加者};
use super::manifold_solution::接触点集合の法線の同時解;
use crate::rigid_body::質量特性;
use crate::rigid_xpbd::{姿勢自由度の参加者, 姿勢自由度の補正};
use crate::xpbd::ラグランジュ乗数;

const 食い込ませる高さ: f32 = -0.01;
const 底面の半分の長さ: f32 = 0.5;

fn 底面の四隅の局所点() -> [変位<ローカル>; 4] {
    [
        局所の変位を作る(底面の半分の長さ, 0.0, 底面の半分の長さ),
        局所の変位を作る(底面の半分の長さ, 0.0, -底面の半分の長さ),
        局所の変位を作る(-底面の半分の長さ, 0.0, 底面の半分の長さ),
        局所の変位を作る(-底面の半分の長さ, 0.0, -底面の半分の長さ),
    ]
}

// 局所接触点をそのまま高さ0の床の点に対応させた拘束。食い込みは参加者の高さで与える。
fn 四隅の接触拘束() -> Vec<剛体と静的世界の接触拘束> {
    底面の四隅の局所点()
        .into_iter()
        .map(|局所点| {
            let 引数 = 剛体と静的世界の接触拘束の引数 {
                剛体側の局所接触点: 局所点,
                静的世界側の接触点: 世界の位置を作る(局所点.x().値(), 0.0, 局所点.z().値()),
                ..剛体と静的世界の基本の引数()
            };
            剛体と静的世界の接触拘束::引数と刻み幅から生成する(引数, 試験の刻み幅()).unwrap()
        })
        .collect()
}

fn 試験の質量特性() -> 質量特性 {
    質量特性を作る(1.0, 1.0)
}

fn 隔たりを測る(拘束: &剛体と静的世界の接触拘束, 参加者: &姿勢自由度の参加者) -> メートル {
    拘束.同時解法の一行にする(参加者).隔たり()
}

#[test]
fn 接触点が一つの集合では逐次の射影と同じ乗数の増分になる() {
    let 参加者 = 高さの参加者(食い込ませる高さ);
    let mut 拘束 = 剛体と静的世界の接触拘束::引数と刻み幅から生成する(剛体と静的世界の基本の引数(), 試験の刻み幅()).unwrap();
    let 行 = [拘束.同時解法の一行にする(&参加者)];
    let 同時解 = 接触点集合の法線の同時解::接触点集合を同時に解く(&行);
    拘束.一回射影する(&参加者);
    let 逐次の増分 = 拘束.法線のラグランジュ乗数().値();
    let 同時の増分 = 同時解.一行の乗数の増分(0).値();
    assert!(逐次の増分 > 0.0, "材料が食い込んでいない");
    assert!(
        (同時の増分 - 逐次の増分).abs() / 逐次の増分 < 1.0e-3,
        "1点の集合で同時解{同時の増分}が逐次の射影{逐次の増分}と一致しない"
    );
}

#[test]
fn 面と面の四点の特異な連立でも全部の点に法線の乗数が載る() {
    let 参加者 = 高さの参加者(食い込ませる高さ);
    let 拘束 = 四隅の接触拘束();
    let 行: Vec<_> = 拘束.iter().map(|拘束| 拘束.同時解法の一行にする(&参加者)).collect();
    let 同時解 = 接触点集合の法線の同時解::接触点集合を同時に解く(&行);
    let 最大 = (0..4).map(|番号| 同時解.一行の乗数の増分(番号).値()).fold(0.0, f32::max);
    for 番号 in 0..4 {
        let 増分 = 同時解.一行の乗数の増分(番号).値();
        assert!(増分 > 0.0, "四隅の{番号}番目に法線の乗数が載っていない: {増分}");
        assert!((増分 - 最大).abs() / 最大 < 1.0e-3, "対称な四隅の乗数が揃っていない: {増分} と {最大}");
    }
}

#[test]
fn 求めた増分を一度だけ適用すると四点の食い込みが解ける() {
    let 参加者 = 高さの参加者(食い込ませる高さ);
    let 拘束 = 四隅の接触拘束();
    let 行: Vec<_> = 拘束.iter().map(|拘束| 拘束.同時解法の一行にする(&参加者)).collect();
    let 同時解 = 接触点集合の法線の同時解::接触点集合を同時に解く(&行);
    let mut 補正の合計 = 姿勢自由度の補正::零();
    for (番号, 一行) in 行.iter().enumerate() {
        let 補正 = 一行.乗数の増分を第1の参加者の補正へ分配する(同時解.一行の乗数の増分(番号));
        補正の合計 = 補正の合計.合わせる(&補正);
    }
    let 適用後 = 姿勢自由度の参加者::動的(補正の合計.配置へ適用する(参加者.配置()), &試験の質量特性());
    for (番号, 拘束) in 拘束.iter().enumerate() {
        let 隔たり = 隔たりを測る(拘束, &適用後).値();
        assert!(隔たり.abs() < 1.0e-5, "四隅の{番号}番目の食い込みが解けていない: {隔たり}");
    }
}

#[test]
fn 離れている接触点は乗数を積まない() {
    let 参加者 = 高さの参加者(0.05);
    let 拘束 = 剛体と静的世界の接触拘束::引数と刻み幅から生成する(剛体と静的世界の基本の引数(), 試験の刻み幅()).unwrap();
    let 行 = [拘束.同時解法の一行にする(&参加者)];
    let 同時解 = 接触点集合の法線の同時解::接触点集合を同時に解く(&行);
    assert_eq!(同時解.一行の乗数の増分(0), ラグランジュ乗数::零());
    assert!(隔たりを測る(&拘束, &参加者).値() > 0.0, "材料が離れていない");
}
