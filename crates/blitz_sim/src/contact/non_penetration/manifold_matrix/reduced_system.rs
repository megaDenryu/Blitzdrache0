//! 有効集合に絞った法線の連立(判断12)。行列の全体から有効な行だけを抜き出し、対角へコンプライアンスの
//! 刻み依存量 α̃ を足した (W_AA + α̃I) と定数項を持つ。抜き出した並びともとの行の番号の対応もこの型が持つ。
//! 行列の型から分けているのは、行列が反復1回につき1度組まれるのに対し、この抜き出しが有効集合の組み替えの
//! たびに起きる別の局面だからである。成分と定数項は単位の無い実数であり、外へ出るときにラグランジュ乗数へ戻す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

use blitz_collision::contact_set::接触点の上限;
use blitz_math::{メートル, 逆キログラム};

use super::super::manifold_active_set::法線の有効集合;
use super::factorization::対称な連立の分解;
use super::接触点集合の法線の有効逆質量行列;
use crate::xpbd::ラグランジュ乗数;

/// 有効集合の行だけを抜き出した対称な連立。
pub(super) struct 有効集合に絞った連立 {
    対称行列: [[f32; 接触点の上限]; 接触点の上限], // 毎キログラム
    定数項: [f32; 接触点の上限],                   // メートル
    もとの行の番号: [usize; 接触点の上限],
    個数: usize,
}

impl 有効集合に絞った連立 {
    pub(super) fn 有効な行だけを抜き出す(
        行列: &接触点集合の法線の有効逆質量行列,
        有効集合: &法線の有効集合,
        刻み依存量: &[逆キログラム],
        右辺: &[メートル],
    ) -> Self {
        let mut 絞った = Self {
            対称行列: [[0.0; 接触点の上限]; 接触点の上限],
            定数項: [0.0; 接触点の上限],
            もとの行の番号: [0; 接触点の上限],
            個数: 0,
        };
        for 番号 in 0..行列.次数() {
            if 有効集合.有効か(番号) {
                絞った.もとの行の番号[絞った.個数] = 番号;
                絞った.個数 += 1;
            }
        }
        for k in 0..絞った.個数 {
            let もとのk = 絞った.もとの行の番号[k];
            for l in 0..絞った.個数 {
                絞った.対称行列[k][l] = 行列.成分の値(もとのk, 絞った.もとの行の番号[l]);
            }
            絞った.対称行列[k][k] += 刻み依存量[もとのk].値();
            絞った.定数項[k] = 右辺[もとのk].値();
        }
        絞った
    }

    /// 連立を解き、もとの行の並びへ戻した乗数の増分。有効でない行と従属として落とした行は零である。
    pub(super) fn 解いてもとの並びへ戻す(&self) -> [ラグランジュ乗数; 接触点の上限] {
        let 解 = 対称な連立の分解::分解する(&self.対称行列, self.個数).前進後退代入で解く(&self.定数項);
        let mut 増分 = [ラグランジュ乗数::零(); 接触点の上限];
        for k in 0..self.個数 {
            増分[self.もとの行の番号[k]] = ラグランジュ乗数::有効逆質量で割った長さから生成する(解[k]);
        }
        増分
    }
}
