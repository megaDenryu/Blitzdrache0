//! 接触点集合の法線の有効逆質量行列 W = J M⁻¹ Jᵀ(判断12)。行 i と行 j の結び付き W_ij を接触点の上限の正方の
//! 受け皿へ持ち、有効集合に絞った連立の求解と、求めた増分が動かす隔たりの計算をメソッドで返す。
//! 成分を毎キログラムの実数として内側に閉じるのは、`逆慣性テンソル` が行列を内側へ閉じるのと同じ理由である。
//! 生成の入口と読み出しの口は符号付きの逆質量・メートル・ラグランジュ乗数の単位型であり、実数が外へ出る口は無い。
//! 分解と正則化の数値の道具は法線と接線の連立で共有するため `contact/symmetric_system.rs` が持つ。
//! コンプライアンスの刻み依存量 α̃ はこの行列に入れない。α̃ は連立の対角にだけ足る正則化であり、増分が動かす
//! 隔たり Σ_j W_ij Δλ_j には入らないためである。α̃ を足すのは連立を抜き出す工程である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

mod reduced_system;

use blitz_collision::contact_set::接触点の上限;
use blitz_math::{メートル, 逆キログラム};

use super::super::symmetric_system::特異を避ける正則化を求める;
use super::manifold_active_set::法線の有効集合;
use super::manifold_row::非貫通の接触点集合の一行;
use crate::xpbd::ラグランジュ乗数;
use reduced_system::有効集合に絞った連立;

/// 接触点集合1つの法線の有効逆質量行列。次数は集合の接触点の数である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触点集合の法線の有効逆質量行列 {
    成分: [[f32; 接触点の上限]; 接触点の上限], // 毎キログラム。行列はこの型の内側に閉じる
    次数: usize,
}

impl 接触点集合の法線の有効逆質量行列 {
    /// 接触点集合の行の一覧から組む。W は対称であるため、下三角を求めて上三角へ写す。
    /// 注意: 行の数が接触点の上限を超える集合は衝突数学層の不変条件の破れであり、添字の範囲外として落ちる。
    pub fn 行の一覧から生成する(行: &[非貫通の接触点集合の一行]) -> Self {
        let mut 成分 = [[0.0; 接触点の上限]; 接触点の上限];
        for (i, 自分) in 行.iter().enumerate() {
            for (j, 相手) in 行.iter().enumerate().take(i + 1) {
                let 値 = 自分.有効逆質量の交差の寄与(相手).値();
                成分[i][j] = 値;
                成分[j][i] = 値;
            }
        }
        Self { 成分, 次数: 行.len() }
    }

    /// この行列が持つ行の数。
    pub fn 次数(&self) -> usize {
        self.次数
    }

    /// 有効集合の行だけを解いた乗数の増分。有効でない行と従属として落とした行の増分は零である。
    pub fn 有効集合で解く(
        &self,
        有効集合: &法線の有効集合,
        刻み依存量: &[逆キログラム],
        右辺: &[メートル],
    ) -> [ラグランジュ乗数; 接触点の上限] {
        有効集合に絞った連立::有効な行だけを抜き出す(self, 有効集合, 刻み依存量, 右辺).解いてもとの並びへ戻す()
    }

    /// 特異な連立を避けるために対角へ足す正則化。残る食い込みは正則化 × 乗数(実測の桁で1e-9メートル)である。
    pub fn 特異を避ける正則化(&self) -> 逆キログラム {
        逆キログラム::生成する(特異を避ける正則化を求める(&self.成分, self.次数))
            .unwrap_or_else(|誤り| panic!("対角の成分は0以上の有限値である: {誤り}"))
    }

    /// 求めた乗数の増分がこの行の隔たりを動かす長さ Σ_j W_ij Δλ_j。侵入が残る行を拾うために読む。
    pub fn 増分が動かす隔たり(&self, 行の番号: usize, 乗数の増分: &[ラグランジュ乗数]) -> メートル {
        let mut 合計 = 0.0;
        for (j, 増分) in 乗数の増分.iter().enumerate().take(self.次数) {
            合計 += self.成分[行の番号][j] * 増分.値();
        }
        メートル::生成する(合計)
    }

    // 抜き出しの工程が読む成分。行列を型の内側へ閉じたまま、子モジュールにだけ実数を見せる。
    fn 成分の値(&self, 行: usize, 列: usize) -> f32 {
        self.成分[行][列]
    }
}
