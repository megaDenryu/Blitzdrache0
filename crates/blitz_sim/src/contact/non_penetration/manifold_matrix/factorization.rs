//! 有効集合に絞った対称な連立の LDLᵀ 分解と、その分解を使う前進後退代入(判断12)。
//! 分解を連立の型から分けているのは、分解が「どの行が従属か」という連立と別の生成物を所有するためである。
//! 面と面の接触では連立が特異になる。剛体1つの法線方向の自由度は並進1つと回転2つの3つしかなく、4点の行は
//! そのうち3つしか張らないためである。枢軸が対角の規模に対して小さすぎる行を従属として落とし、その行の解を
//! 零に置く。落とす判定は行の番号の昇順で行い、先に来た行を残す(同じ入力から同じ解が出るため)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

use blitz_collision::contact_set::接触点の上限;

// 枢軸を従属と見なす比。対角の最大に対してこれより小さい枢軸の行は連立から落とす。
const 従属と見なす枢軸の比: f32 = 1.0e-6;

/// 対称な連立 A = L D Lᵀ の分解。従属として落とした行の印を一緒に持つ。
pub(super) struct 対称な連立の分解 {
    下三角: [[f32; 接触点の上限]; 接触点の上限],
    対角: [f32; 接触点の上限],
    残す: [bool; 接触点の上限],
    個数: usize,
}

impl 対称な連立の分解 {
    pub(super) fn 分解する(対称行列: &[[f32; 接触点の上限]; 接触点の上限], 個数: usize) -> Self {
        let mut 分解 = Self {
            下三角: [[0.0; 接触点の上限]; 接触点の上限],
            対角: [1.0; 接触点の上限],
            残す: [false; 接触点の上限],
            個数,
        };
        let 枢軸の下限 = 従属と見なす枢軸の比 * 対角の最大(対称行列, 個数);
        for k in 0..個数 {
            let 枢軸 = 分解.第k行の下三角を埋めて残る枢軸を求める(対称行列, k);
            分解.残す[k] = 枢軸 > 枢軸の下限;
            分解.対角[k] = if 分解.残す[k] { 枢軸 } else { 1.0 };
        }
        分解
    }

    /// L D Lᵀ x = 定数項 の解。従属として落とした行の解は零である。
    pub(super) fn 前進後退代入で解く(&self, 定数項: &[f32; 接触点の上限]) -> [f32; 接触点の上限] {
        let mut 途中 = [0.0; 接触点の上限];
        for k in 0..self.個数 {
            if !self.残す[k] {
                continue;
            }
            let mut 値 = 定数項[k];
            for (m, 途中の値) in 途中.iter().enumerate().take(k) {
                if self.残す[m] {
                    値 -= self.下三角[k][m] * 途中の値;
                }
            }
            途中[k] = 値;
        }
        let mut 解 = [0.0; 接触点の上限];
        for k in (0..self.個数).rev() {
            if !self.残す[k] {
                continue;
            }
            let mut 値 = 途中[k] / self.対角[k];
            for (m, 解の値) in 解.iter().enumerate().take(self.個数).skip(k + 1) {
                if self.残す[m] {
                    値 -= self.下三角[m][k] * 解の値;
                }
            }
            解[k] = 値;
        }
        解
    }

    // 第k行の下三角の成分を埋め、対角へ残る枢軸 A_kk − Σ_m L_km² D_m を返す。
    fn 第k行の下三角を埋めて残る枢軸を求める(
        &mut self, 対称行列: &[[f32; 接触点の上限]; 接触点の上限], k: usize
    ) -> f32 {
        let mut 枢軸 = 対称行列[k][k];
        // 対称であるため A_km は m 行の k 列から読める。行を走らせると、下三角の書き込みと読みの借用が分かれる。
        for (m, 第m行) in 対称行列.iter().enumerate().take(k) {
            if !self.残す[m] {
                continue;
            }
            let mut 値 = 第m行[k];
            for p in 0..m {
                if self.残す[p] {
                    値 -= self.下三角[k][p] * self.対角[p] * self.下三角[m][p];
                }
            }
            self.下三角[k][m] = 値 / self.対角[m];
            枢軸 -= self.下三角[k][m] * self.下三角[k][m] * self.対角[m];
        }
        枢軸
    }
}

fn 対角の最大(対称行列: &[[f32; 接触点の上限]; 接触点の上限], 個数: usize) -> f32 {
    (0..個数).map(|k| 対称行列[k][k]).fold(0.0, f32::max)
}
