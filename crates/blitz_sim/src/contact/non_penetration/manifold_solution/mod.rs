//! 接触点集合の法線を同時に解いた結果(判断12)。集合の全部の行を1つの連立として解き、点ごとの乗数の増分を返す。
//! 点を順に配置へ適用しないのは、点Aの補正が点Bを離し、次の巡回でAの乗数を解放する往復が起きるためである。
//! この往復は反復回数を増やすほど法線の乗数の合計を真の法線力積から離す(実測は `_doc/計測/剛体の接触の摩擦と反発_2026-09-03.md`)。
//! 有効集合の組み替えは、乗数が負に振れた行を外し、増分を適用しても侵入が残る行を入れる、を決まった上限の回数だけ繰り返す。
//! 打ち切ったときも上限と0の間への切り詰めが片側性を守るため、解が拘束を破る向きへ出ることはない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

mod iteration;

use blitz_collision::contact_set::接触点の上限;

use super::manifold_row::非貫通の接触点集合の一行;
use crate::xpbd::ラグランジュ乗数;
use iteration::法線の同時解の巡回;

// 有効集合を組み替える上限の回数。1回の組み替えで1行が出入りするため、接触点の上限の2倍で足りる。
const 有効集合を組み替える上限の回数: usize = 2 * 接触点の上限;

/// 接触点集合1つの法線を同時に解いた結果。行の並びは渡した行の一覧と同じである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触点集合の法線の同時解 {
    乗数の増分: [ラグランジュ乗数; 接触点の上限],
}

impl 接触点集合の法線の同時解 {
    /// 接触点集合の行の一覧を1つの連立として解く。
    /// 注意: 行の数が接触点の上限を超える集合は衝突数学層の不変条件の破れであり、添字の範囲外として落ちる。
    pub fn 接触点集合を同時に解く(行: &[非貫通の接触点集合の一行]) -> Self {
        let mut 巡回 = 法線の同時解の巡回::始める(行);
        for _ in 0..有効集合を組み替える上限の回数 {
            巡回.有効集合で解き直す();
            if let Some(番号) = 巡回.乗数が負になる最初の行() {
                巡回.有効集合から外す(番号);
                continue;
            }
            if let Some(番号) = 巡回.侵入が残る最初の行() {
                巡回.有効集合へ入れる(番号);
                continue;
            }
            break;
        }
        Self {
            乗数の増分: 巡回.上限で切り詰めた乗数の増分(),
        }
    }

    /// 指定の行の乗数の増分。
    pub fn 一行の乗数の増分(&self, 行の番号: usize) -> ラグランジュ乗数 {
        self.乗数の増分[行の番号]
    }
}
