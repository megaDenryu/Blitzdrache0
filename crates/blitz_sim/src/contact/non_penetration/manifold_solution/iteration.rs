//! 接触点集合の法線の有効集合を組み替えながら連立を解き直す途中の状態(判断12)。行の一覧・有効逆質量行列・
//! 有効集合・いまの乗数の増分を保持し、1巡ぶんの求解と、外す行・入れる行の判定をメソッドで持つ。
//! 結果の型から分けているのは、こちらが巡回のあいだ書き換わる状態を所有し、結果が巡回の後に凍る値だからである。
//!   有効な行 i:   Σ_{j∈A} (W + (α̃ + ε)I)_ij Δλ_j = −d_i − α̃ λ_i + Σ_{j∉A} W_ij λ_j
//!   有効でない行 j: Δλ_j = −λ_j(乗数を解放して有効集合から外れる)
//! 特異を避ける正則化 ε を右辺へ足さないのは、増分の求解だけを鈍らせ、収束の到達点(増分が零のとき d = −α̃ λ、
//! 硬い接触なら食い込み零)を変えないためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

use blitz_collision::contact_set::接触点の上限;
use blitz_math::{メートル, 逆キログラム};

use super::super::manifold_active_set::法線の有効集合;
use super::super::manifold_matrix::接触点集合の法線の有効逆質量行列;
use super::super::manifold_row::非貫通の接触点集合の一行;
use crate::xpbd::ラグランジュ乗数;

// 特異な連立を避ける正則化の比。面と面の接触では剛体1つの法線方向の自由度が並進1つと回転2つの3つしかなく、
// 4点の行はそのうち3つしか張らない。従属の行を落とすと、載る荷重が一部の点へ偏って残りの点の乗数が0になり、
// 判断14の速度段階がその点を接触していない点として外す。対角へこの比の正則化を足すと連立が正則になり、
// 荷重が集合の全部の点へ最小のノルムの配分で載る。残る食い込みは正則化 × 乗数(実測の桁で1e-9メートル)である。
const 特異を避ける正則化の比: f32 = 1.0e-4;

pub(super) struct 法線の同時解の巡回<'行の一覧> {
    行: &'行の一覧 [非貫通の接触点集合の一行],
    行列: 接触点集合の法線の有効逆質量行列,
    有効集合: 法線の有効集合,
    刻み依存量: [逆キログラム; 接触点の上限],
    乗数の増分: [ラグランジュ乗数; 接触点の上限],
}

impl<'行の一覧> 法線の同時解の巡回<'行の一覧> {
    pub(super) fn 始める(行: &'行の一覧 [非貫通の接触点集合の一行]) -> Self {
        let 行列 = 接触点集合の法線の有効逆質量行列::行の一覧から生成する(行);
        let 正則化 = 特異を避ける正則化の比を対角の最大へ掛ける(&行列);
        let mut 刻み依存量 = [逆キログラム::零(); 接触点の上限];
        for (番号, 一行) in 行.iter().enumerate() {
            刻み依存量[番号] = 一行.刻み依存量() + 正則化;
        }
        Self {
            行,
            行列,
            有効集合: 法線の有効集合::貫通と乗数から始める(行),
            刻み依存量,
            乗数の増分: [ラグランジュ乗数::零(); 接触点の上限],
        }
    }

    /// いまの有効集合で連立を解き直す。有効でない行の増分は乗数を零へ解放する値である。
    pub(super) fn 有効集合で解き直す(&mut self) {
        let mut 解放の増分 = [ラグランジュ乗数::零(); 接触点の上限];
        for (番号, 一行) in self.行.iter().enumerate() {
            if !self.有効集合.有効か(番号) {
                解放の増分[番号] = ラグランジュ乗数::零() - 一行.法線のラグランジュ乗数();
            }
        }
        let mut 右辺 = [メートル::生成する(0.0); 接触点の上限];
        for (番号, 一行) in self.行.iter().enumerate() {
            右辺[番号] =
                一行.隔たり() * -1.0 - 一行.法線のラグランジュ乗数() * 一行.刻み依存量() - self.行列.増分が動かす隔たり(番号, &解放の増分);
        }
        self.乗数の増分 = self.行列.有効集合で解く(&self.有効集合, &self.刻み依存量, &右辺);
        for (番号, 解放) in 解放の増分.iter().enumerate().take(self.行.len()) {
            if !self.有効集合.有効か(番号) {
                self.乗数の増分[番号] = *解放;
            }
        }
    }

    /// 有効な行のうち、解いた乗数が負に振れた行。最も負の行を選び、同じ値なら小さい番号を採る。
    pub(super) fn 乗数が負になる最初の行(&self) -> Option<usize> {
        let mut 選んだ = None;
        let mut 最も負の値 = ラグランジュ乗数::零();
        for (番号, 一行) in self.行.iter().enumerate() {
            let 解いた乗数 = 一行.法線のラグランジュ乗数() + self.乗数の増分[番号];
            if self.有効集合.有効か(番号) && 解いた乗数 < 最も負の値 {
                最も負の値 = 解いた乗数;
                選んだ = Some(番号);
            }
        }
        選んだ
    }

    /// 有効でない行のうち、増分を適用しても侵入が残る行。最も深い行を選び、同じ値なら小さい番号を採る。
    pub(super) fn 侵入が残る最初の行(&self) -> Option<usize> {
        let mut 選んだ = None;
        let mut 最も深い隔たり = メートル::生成する(0.0);
        for (番号, 一行) in self.行.iter().enumerate() {
            let 補正後の隔たり = 一行.隔たり() + self.行列.増分が動かす隔たり(番号, &self.乗数の増分);
            let 拾える = !self.有効集合.有効か(番号) && !一行.動かせない組か();
            if 拾える && 補正後の隔たり < 最も深い隔たり {
                最も深い隔たり = 補正後の隔たり;
                選んだ = Some(番号);
            }
        }
        選んだ
    }

    pub(super) fn 有効集合から外す(&mut self, 番号: usize) {
        self.有効集合.外す(番号);
    }

    pub(super) fn 有効集合へ入れる(&mut self, 番号: usize) {
        self.有効集合.入れる(番号);
    }

    /// 乗数を0以上とこの細分の上限の間へ収めた増分。片側性と、1細分で詰めてよい長さの上限をここで守る。
    pub(super) fn 上限で切り詰めた乗数の増分(&self) -> [ラグランジュ乗数; 接触点の上限] {
        let mut 切り詰めた = [ラグランジュ乗数::零(); 接触点の上限];
        for (番号, 一行) in self.行.iter().enumerate() {
            if 一行.動かせない組か() {
                continue;
            }
            let 乗数 = 一行.法線のラグランジュ乗数();
            切り詰めた[番号] = (乗数 + self.乗数の増分[番号]).区間へ収める(ラグランジュ乗数::零(), 一行.乗数の上限()) - 乗数;
        }
        切り詰めた
    }
}

// 連立の対角へ足す正則化。大きさは行列の規模(対角の最大)に比例させ、質量と腕の取り方に依らないようにする。
fn 特異を避ける正則化の比を対角の最大へ掛ける(行列: &接触点集合の法線の有効逆質量行列) -> 逆キログラム {
    let 値 = 特異を避ける正則化の比 * 行列.対角の最大().値();
    逆キログラム::生成する(値).unwrap_or_else(|誤り| panic!("対角の最大は0以上の有限値である: {誤り}"))
}
