//! 剛体と静的世界の接触拘束の静的な引数(判断11の表の右の行)。剛体の側は重心局所の接触点を持ち、静的世界の側は
//! 細分の間に動かない世界位置を持つ。静的世界には剛体の識別子も重心も無いため、剛体Bを要求する1つの型へ潰せない。
//! 欄を名前付きで持つのは、同じ型の値が並ぶ組み立てで位置による取り違えを起こさないためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use blitz_math::{ローカル, ワールド, 位置, 変位, 方向};

use super::contact_property::接触物性;
use super::feature_identity::接触の特徴の識別;
use super::non_penetration::非貫通の解き方;
use super::penetration_depth::貫通量;
use super::static_world_partner_id::静的世界の接触相手の識別子;
use crate::rigid_body::剛体の識別子;

/// 剛体と静的世界の接触点1つが持つ、細分の間に変わらない値。接触法線は剛体から静的世界へ向かう。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 剛体と静的世界の接触拘束の引数 {
    pub 剛体: 剛体の識別子,
    pub 静的世界の接触相手: 静的世界の接触相手の識別子,
    pub 剛体側の局所接触点: 変位<ローカル>,
    pub 静的世界側の接触点: 位置<ワールド>,
    pub 接触法線: 方向<ワールド>,
    pub 生成時の貫通量: 貫通量,
    pub 特徴の識別: 接触の特徴の識別,
    pub 接触物性: 接触物性,
    pub 解き方: 非貫通の解き方,
}
