//! 接触に参加する剛体: 接触拘束の生成が読む剛体の側の情報(判断11)。識別子・予測した配置・材質の識別子・形の最小の厚みを持つ。
//! 接触点集合が返した点を各剛体の重心局所座標へ写すのはこの型のメソッドである。写しを剛体の側が行うのは、
//! 衝突数学層が剛体の重心も姿勢も知らないためである。局所点で持つことで、細分の間に剛体が動いても現在の姿勢で貫通量を
//! 再評価できる(判断12)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use blitz_collision::shape::形の局所座標の位置;
use blitz_math::{ローカル, 変位};

use super::generation_error::接触拘束の生成エラー;
use super::material_id::材質の識別子;
use super::minimum_thickness::形の最小の厚み;
use super::shared_frame::接触点の位置をワールドへ写す;
use crate::rigid_body::{剛体の識別子, 配置};

/// 接触拘束の生成に参加する1つの剛体。配置は細分の予測が作った配置である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触に参加する剛体 {
    識別子: 剛体の識別子,
    配置: 配置,
    材質: 材質の識別子,
    形の最小の厚み: 形の最小の厚み,
}

impl 接触に参加する剛体 {
    /// 台帳が持つ剛体の識別子と予測した配置、その衝突形状が参照する材質と厚みから作る。
    pub fn 生成する(
        識別子: 剛体の識別子, 配置: 配置, 材質: 材質の識別子, 形の最小の厚み: 形の最小の厚み
    ) -> Self {
        Self {
            識別子,
            配置,
            材質,
            形の最小の厚み,
        }
    }

    /// 接触の履歴の鍵と反復の順序が読む識別子。
    pub fn 識別子(&self) -> 剛体の識別子 {
        self.識別子
    }

    /// 接触物性を混合則へ問い合わせるための材質の識別子。
    pub fn 材質(&self) -> 材質の識別子 {
        self.材質
    }

    /// 深い初期重なりの切り詰めの上限に使う厚み。
    pub fn 形の最小の厚み(&self) -> 形の最小の厚み {
        self.形の最小の厚み
    }

    /// 接触点集合が返した自分の形の上の点を、自分の重心局所座標の点 r̄ = R(q)ᵀ (p − x) へ写す。
    pub fn 接触点を重心局所へ写す(
        &self,
        共有の座標系の点: 形の局所座標の位置,
    ) -> Result<変位<ローカル>, 接触拘束の生成エラー> {
        Ok(self.配置.世界位置を重心局所へ写す(接触点の位置をワールドへ写す(共有の座標系の点)?))
    }
}
