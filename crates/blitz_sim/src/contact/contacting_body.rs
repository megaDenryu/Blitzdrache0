//! 接触に参加する剛体: 接触拘束の生成が読む剛体の側の情報(判断11)。識別子・予測した配置・材質の識別子・形の最小の厚み・
//! 衝突の問い合わせの基準原点を持つ。衝突数学層へ渡す形は基準原点に相対な直方体としてこの型が組み、接触点集合が返した点を
//! 重心局所座標へ写すのもこの型のメソッドである。写しを剛体の側が行うのは、衝突数学層が剛体の重心も姿勢も知らないためである。
//! 局所点で持つことで、細分の間に剛体が動いても現在の姿勢で符号付き貫通量を再評価できる(判断12)。
//! 基準原点を持つのは、渡した形の中心と返った点から引く中心が同じ1つの値から出ることを型で保つためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use blitz_collision::shape::{任意姿勢の直方体, 形の局所座標の位置, 直方体の軸ごとの半分の長さ};
use blitz_math::{ローカル, 位置, 変位};

use super::generation_error::接触拘束の生成エラー;
use super::material_id::材質の識別子;
use super::minimum_thickness::形の最小の厚み;
use super::query_origin::衝突の問い合わせの基準原点;
use super::shared_frame::接触点を渡した相対の中心からの変位へ写す;
use crate::rigid_body::{剛体の識別子, 配置};

/// 接触拘束の生成に参加する1つの剛体。配置は細分の予測が作った配置である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触に参加する剛体 {
    識別子: 剛体の識別子,
    配置: 配置,
    材質: 材質の識別子,
    形の最小の厚み: 形の最小の厚み,
    基準原点: 衝突の問い合わせの基準原点,
}

impl 接触に参加する剛体 {
    /// 台帳が持つ剛体の識別子と予測した配置、その衝突形状が参照する材質と厚み、この問い合わせの基準原点から作る。
    pub fn 生成する(
        識別子: 剛体の識別子,
        配置: 配置,
        材質: 材質の識別子,
        形の最小の厚み: 形の最小の厚み,
        基準原点: 衝突の問い合わせの基準原点,
    ) -> Self {
        Self {
            識別子,
            配置,
            材質,
            形の最小の厚み,
            基準原点,
        }
    }

    /// 接触の履歴の鍵と反復の順序が読む識別子。
    pub fn 識別子(&self) -> 剛体の識別子 {
        self.識別子
    }

    /// 接触物性を混合則へ問い合わせるための材質の識別子。
    pub fn 材質(&self) -> 材質の識別子 {
        self.材質
    }

    /// 深い初期重なりの切り詰めの上限に使う厚み。
    pub fn 形の最小の厚み(&self) -> 形の最小の厚み {
        self.形の最小の厚み
    }

    /// この剛体が形を組み、返った点を写すときの基準原点。剛体どうしの対では2つの参加者がこれを共有する。
    pub fn 基準原点(&self) -> 衝突の問い合わせの基準原点 {
        self.基準原点
    }

    /// 同じ剛体を別の基準原点で読む参加者。剛体どうしの対では第2の参加者を第1の参加者の基準原点へ付け替える。
    pub fn 基準原点を付け替える(&self, 基準原点: 衝突の問い合わせの基準原点) -> Self {
        Self { 基準原点, ..*self }
    }

    /// 衝突数学層へ渡す、基準原点に相対な直方体。その中心が、返った点を写すときに引く相対の中心である。
    pub fn 衝突へ渡す直方体(
        &self,
        半分の長さ: 直方体の軸ごとの半分の長さ,
    ) -> Result<任意姿勢の直方体, 接触拘束の生成エラー> {
        self.基準原点.剛体の相対の直方体を組む(&self.配置, 半分の長さ)
    }

    /// 接触点集合が返した自分の形の上の点を、自分の重心局所座標の点 r̄ = R(q)ᵀ (p − 渡した相対の中心) へ写す。
    /// 引くのは衝突数学層へ渡した相対の中心であり、真の重心との差は丸めであるため、局所点を世界へ戻した点は真の位置での形の表面の点になる(判断3)。
    pub fn 接触点を重心局所へ写す(
        &self,
        共有の座標系の点: 形の局所座標の位置,
    ) -> Result<変位<ローカル>, 接触拘束の生成エラー> {
        let 相対の中心: 位置<ローカル> = self.基準原点.剛体の相対の中心を求める(&self.配置);
        Ok(self.配置.姿勢().逆回転().変位を回す(接触点を渡した相対の中心からの変位へ写す(
            共有の座標系の点,
            相対の中心,
        )?))
    }
}
