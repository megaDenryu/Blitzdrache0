fn 上下の箱の接触点集合(上: &配置, 下: &配置) -> 接触点集合<直方体どうしの接触の特徴の対> {
    let 二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) = 新形で問い合わせる(上, 下, 半分の長さ(立方体の半分の長さ))
    else {
        panic!("上下の箱が食い込んでいるのに接触点集合が返らない");
    };
    集合
}

fn 組み立てを作る(混合則: &混合則) -> 接触拘束のバッチの組み立て<'_> {
    接触拘束のバッチの組み立て::生成する(混合則, コンプライアンス::硬い(), 試験の刻み幅(), 1)
}

/// 1剛体の往復: 衝突数学層が返す点は相対の中心 + r̄ である。それを写した局所点は r̄ に戻り、世界へ戻した点は真の重心 + r̄ になる。
#[test]
fn 渡した相対の中心を引いて写した局所点は世界へ戻すと真の位置での表面の点になる() {
    let 細かい = 二十メートルの帯の刻み() * 0.3;
    let 配置 = 細かい位置を持つ配置(20.5, 細かい, 細かい);
    let mut 台帳 = 剛体の台帳::空();
    let 剛体 = 参加者を作る(&mut 台帳, 配置, 衝突の問い合わせの基準原点::剛体の粗い位置から選ぶ(&配置));
    let 表面の局所点 = 局所の変位を作る(0.5, -0.5, 0.5);
    let 相対の中心 = 剛体.基準原点().剛体の相対の中心を求める(&配置);
    let 返った点 = 形の局所座標の位置::生成する(
        f64::from(相対の中心.x().値()) + 0.5,
        f64::from(相対の中心.y().値()) - 0.5,
        f64::from(相対の中心.z().値()) + 0.5,
    )
    .unwrap();
    let 局所点 = 剛体.接触点を重心局所へ写す(返った点).unwrap();
    assert!((局所点 - 表面の局所点).長さ().値() < 1.0e-7, "{局所点:?}");
    let 戻した = 配置.局所点の世界位置(局所点).倍精度で評価した位置();
    let 真の重心 = 配置.重心の位置().倍精度で評価した位置();
    assert!((戻した.x().値() - (真の重心.x().値() + 0.5)).abs() < 1.0e-9);
    assert!((戻した.y().値() - (真の重心.y().値() - 0.5)).abs() < 1.0e-9);
    assert!((真の重心.y().値() - f64::from(20.5f32) - f64::from(細かい)).abs() < 1.0e-12);
}

/// 細かい位置を持つ上下の箱の接触点集合を第1の参加者の粗い位置を原点に積むと、両剛体の局所点を世界へ戻した点が真の表面の上にある。
#[test]
fn 細かい位置を持つ二つの剛体の局所点は真の表面の上へ戻る() {
    let 細かい = 二十メートルの帯の刻み() * 0.3;
    let (上の配置, 下の配置) = (細かい位置を持つ配置(20.5 - 1.0e-4, 0.0, -細かい), 細かい位置を持つ配置(19.5, 0.0, 細かい));
    let 基準原点 = 衝突の問い合わせの基準原点::剛体の粗い位置から選ぶ(&上の配置);
    let mut 台帳 = 剛体の台帳::空();
    let (上, 下) = (参加者を作る(&mut 台帳, 上の配置, 基準原点), 参加者を作る(&mut 台帳, 下の配置, 基準原点));
    let 集合 = 上下の箱の接触点集合(&上の配置, &下の配置);
    let 混合則 = 単一の材質の混合則();
    let mut 組み立て = 組み立てを作る(&混合則);
    組み立て.剛体どうしの接触点集合を積む(&上, &下, &集合).unwrap();
    let バッチ = 組み立て.二つのバッチを組み立てる();
    assert_eq!(バッチ.剛体どうしの接触拘束().len(), 4);
    for 拘束 in バッチ.剛体どうしの接触拘束() {
        let 上の底面の高さ = 上の配置.重心の位置().倍精度で評価した位置().y().値() - 0.5;
        let 下の上面の高さ = 下の配置.重心の位置().倍精度で評価した位置().y().値() + 0.5;
        let 上の点 = 上の配置.局所点の世界位置(拘束.引数().局所接触点a).倍精度で評価した位置();
        let 下の点 = 下の配置.局所点の世界位置(拘束.引数().局所接触点b).倍精度で評価した位置();
        assert!(
            (上の点.y().値() - 上の底面の高さ).abs() < 1.0e-7,
            "上の局所点が底面から外れた: {上の点:?}"
        );
        assert!(
            (下の点.y().値() - 下の上面の高さ).abs() < 1.0e-7,
            "下の局所点が上面から外れた: {下の点:?}"
        );
    }
}

/// 別の基準原点で組んだ2つの参加者は積めない。返った点の座標系が一致しないためである。
#[test]
fn 基準原点が違う二つの剛体を積むと型付きエラーで拒む() {
    let (上の配置, 下の配置) = (細かい位置を持つ配置(20.5 - 1.0e-4, 0.0, 0.0), 細かい位置を持つ配置(19.5, 0.0, 0.0));
    let mut 台帳 = 剛体の台帳::空();
    let 上 = 参加者を作る(&mut 台帳, 上の配置, 衝突の問い合わせの基準原点::剛体の粗い位置から選ぶ(&上の配置));
    let 下 = 参加者を作る(&mut 台帳, 下の配置, 衝突の問い合わせの基準原点::剛体の粗い位置から選ぶ(&下の配置));
    let 集合 = 上下の箱の接触点集合(&上の配置, &下の配置);
    let 混合則 = 単一の材質の混合則();
    let mut 組み立て = 組み立てを作る(&混合則);
    assert!(matches!(
        組み立て.剛体どうしの接触点集合を積む(&上, &下, &集合),
        Err(接触拘束の生成エラー::二つの剛体の基準原点が違う { .. })
    ));
}
