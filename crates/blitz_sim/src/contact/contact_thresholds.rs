//! 接触の速度段階(判断14)と休止(判断18)が読む閾値を1箇所に置く。値の根拠を各行の末尾に書く。
//! 1箇所に集めるのは、同じ意味の閾値が速度段階と休止の判定に散ると、箱の塔と落下する箱の実測で確定する日に
//! 直す場所が2つになるためである。いずれも初期値であり、実測の日に確定する。
//! 低速の反発の抑制の閾値だけが関数なのは、値が刻み幅と重力に依るためである。刻み幅と無関係な定数にすると、
//! 細分数を変えたときに1細分の自由落下で付く速度との関係が壊れる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

use blitz_math::{メートル毎秒, ラジアン毎秒};

use crate::constraint_graph::一様な加速度;
use crate::xpbd::刻み幅;

const 自由落下の速度に掛ける倍率: f32 = 2.0; // 1細分の自由落下で付く速度そのものを閾値にすると、静置した箱の毎細分の接近が抑制の外へ出る
const 休止と判定する速さ: f32 = 0.01; // メートル毎秒。1細分(1/480秒)で接触余白0.005メートルより十分に小さくしか動かない速さ
const 休止と判定する回る速さ: f32 = 0.05; // ラジアン毎秒。半分の長さ0.5メートルの箱の角が1細分で動く長さが接触余白より小さい回り方

/// 島の全部の動的剛体が静穏である細分がこの個数だけ続くと島が休止する(判断18)。
pub const 休止と判定する連続細分数: u32 = 60; // 8細分の刻みで7.5刻み(0.125秒)ぶんであり、跳ね返りの往復より長い

/// 低速の反発の抑制の閾値 v_閾値 = 2 |g| h(判断14)。法線相対速度の大きさがこれ以下なら反発係数を0として扱う。
/// 重力由来の微小な接近速度を衝突と誤認して静置した箱が毎刻み微小に跳ねることを断つ。
pub fn 反発を抑制する法線相対速度の閾値(重力: 一様な加速度, 刻み幅: 刻み幅) -> メートル毎秒 {
    重力.一刻みの速度の変化(刻み幅).長さ().比で伸ばす(自由落下の速度に掛ける倍率)
}

/// 静穏の判定が動的剛体の並進速度と比べる閾値 v_休止(判断18)。
pub fn 休止と判定する並進速度の閾値() -> メートル毎秒 {
    メートル毎秒::生成する(休止と判定する速さ)
}

/// 静穏の判定が動的剛体の角速度と比べる閾値 ω_休止(判断18)。
pub fn 休止と判定する角速度の閾値() -> ラジアン毎秒 {
    ラジアン毎秒::生成する(休止と判定する回る速さ)
}
