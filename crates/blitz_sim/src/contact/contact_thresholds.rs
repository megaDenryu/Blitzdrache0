//! 接触点集合の生成(判断11)と接触の速度段階(判断14)と休止(判断18)が読む閾値を1箇所に置く。値の根拠を各行の末尾に書く。
//! 1箇所に集めるのは、同じ意味の閾値が速度段階と休止の判定に散ると、箱の塔と落下する箱の実測で確定する日に
//! 直す場所が2つになるためである。いずれも初期値であり、実測の日に確定する。
//! 低速の反発の抑制の閾値だけが関数なのは、値が刻み幅と重力に依るためである。刻み幅と無関係な定数にすると、
//! 細分数を変えたときに1細分の自由落下で付く速度との関係が壊れる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

use blitz_collision::contact_set::{接触点集合の問い合わせエラー, 接触生成の余白メートル};
use blitz_math::{メートル毎秒, ラジアン毎秒, 秒};
use thiserror::Error;

use crate::constraint_graph::一様な加速度;
use crate::rigid_body::静穏が続いた細分の本数;
use crate::xpbd::刻み幅;

const 自由落下の速度に掛ける倍率: f32 = 2.0; // 1細分の自由落下で付く速度そのものを閾値にすると、静置した箱の毎細分の接近が抑制の外へ出る
const 接触生成の余白のメートル: f64 = 0.005; // 判断11の候補点を保つ範囲。判断12の接触余白と同じ値を置いているが、2つは別の量であり導出は無い(実測は下の関数の注意)
const 休止と判定する速さ: f32 = 0.01; // メートル毎秒。1細分(1/480秒)で接触余白0.005メートルより十分に小さくしか動かない速さ
const 休止と判定する回る速さ: f32 = 0.05; // ラジアン毎秒。半分の長さ0.5メートルの箱の角が1細分で動く長さが接触余白より小さい回り方

const 接触余白の長さ: f32 = 0.005; // メートル。休止の判定の貫通残差の基準(判断12・18)

const 休止と判定する連続静穏の秒数: f32 = 0.125; // 基本刻み1/60秒の7.5本ぶんであり、跳ね返りの往復より長い
const 細分の本数を数える上限: u32 = 100_000; // 閾値の時間に届かないほど細かい刻み幅を、数え続けずに型付きエラーへ変えるための上限

/// 島の全部の動的剛体が静穏である状態がこの物理時間だけ連続すると島が休止する(判断18)。
/// 細分の個数でなく時間で持つのは、細分数という解法品質の設定を変えただけで休止までの物理時間が変わってはならないためである。
/// 細分数8ならこの時間は60細分、16なら120細分に当たる。
pub fn 休止と判定する連続静穏の時間() -> 秒 {
    秒::生成する(休止と判定する連続静穏の秒数)
}

/// 島が休止するのに要る連続静穏の細分の本数(判断18)。上の物理時間0.125秒を細分の刻み幅で数えた本数である。
/// 実行時に秒を積み上げず、この本数を起動時に1度だけ導くのは、単精度の秒を細分ごとに足すと丸めが積もり、
/// 閾値の境目が1本ずれるためである(実測では細分数8で61本目、16で121本目に休止し、正本の60本と120本から1本遅れていた)。
/// 返す本数は、その本数ぶんの物理時間が0.125秒へ本当に達する最小の本数である。閾値を相対的に縮めて到達とみなすことはしない。
/// 縮めると、10本で0.1249999秒しか経っていない刻み幅まで10本で休止する帯ができ、追い出したはずの数値誤差が時間契約へ戻るためである。
pub fn 休止と判定する連続静穏の細分の本数(
    細分の刻み幅: 刻み幅,
) -> Result<静穏が続いた細分の本数, 休止と判定する細分の本数エラー> {
    let 閾値の秒数 = f64::from(休止と判定する連続静穏の秒数);
    let 一本の秒数 = f64::from(細分の刻み幅.秒().値());
    for 本数 in 1..=細分の本数を数える上限 {
        if f64::from(本数) * 一本の秒数 >= 閾値の秒数 {
            return Ok(静穏が続いた細分の本数::本数から生成する(本数));
        }
    }
    Err(休止と判定する細分の本数エラー::細分の刻み幅が細かすぎる {
        細分の刻み幅: 細分の刻み幅.秒(),
        数えた上限: 細分の本数を数える上限,
    })
}

/// 休止の閾値を細分の本数へ写す導出が拒んだ入力。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 休止と判定する細分の本数エラー {
    #[error("細分の刻み幅{細分の刻み幅:?}が細かすぎて、休止と判定する連続静穏の時間が{数えた上限}本の細分に収まらない")]
    細分の刻み幅が細かすぎる { 細分の刻み幅: 秒, 数えた上限: u32 },
}

/// 低速の反発の抑制の閾値 v_閾値 = 2 |g| h(判断14)。法線相対速度の大きさがこれ以下なら反発係数を0として扱う。
/// 重力由来の微小な接近速度を衝突と誤認して静置した箱が毎刻み微小に跳ねることを断つ。
pub fn 反発を抑制する法線相対速度の閾値(重力: 一様な加速度, 刻み幅: 刻み幅) -> メートル毎秒 {
    重力.一刻みの速度の変化(刻み幅).長さ().比で伸ばす(自由落下の速度に掛ける倍率)
}

/// 静穏の判定が動的剛体の並進速度と比べる閾値 v_休止(判断18)。
pub fn 休止と判定する並進速度の閾値() -> メートル毎秒 {
    メートル毎秒::生成する(休止と判定する速さ)
}

/// 静穏の判定が動的剛体の角速度と比べる閾値 ω_休止(判断18)。
pub fn 休止と判定する角速度の閾値() -> ラジアン毎秒 {
    ラジアン毎秒::生成する(休止と判定する回る速さ)
}

/// 静穏の判定が接触の貫通残差と比べる閾値(判断12・18)。
pub fn 休止と判定する接触余白() -> blitz_math::メートル {
    blitz_math::メートル::生成する(接触余白の長さ)
}

/// 接触点集合を組み立てるとき、参照面の平面より外側へ出た切り抜きの角を接触解法の候補点として保つ範囲の長さ(判断11)。
/// 形そのものを膨らませる長さではなく、分離軸の判定にも入らない。
/// 注意: 箱10段の塔の受入条件はいまの値0.005メートルのときだけ落ちる(0.002メートル以下では通る)。
/// 実測は `_doc/計測/塔の接触点集合が一点へ落ちる後退_2026-09-05.md` にある。
pub fn 接触生成の余白() -> Result<接触生成の余白メートル, 接触点集合の問い合わせエラー> {
    接触生成の余白メートル::生成する(接触生成の余白のメートル)
}
