//! 接触拘束のバッチの組み立て(判断11の生成の工程の3段目)。混合則を保持し、候補の対ごとに接触点集合を受け取って、
//! 両形の上の点を各剛体の重心局所座標へ写し、2つのバッチへ積む。索引の更新と候補の列挙(前2段)は細分の工程が持つ。
//! 組み立てを混合則から分けず1つの型にしているのは、接触物性の決定が接触拘束の生成だけの呼び出しであるためである(判断15)。
//! 確保は生成で1度だけ行い、積む工程はヒープを触らない。見込みの対の数に接触点の上限を掛けた長さを先に確保する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use blitz_collision::contact_set::接触点の上限;

use super::body_body_contact::剛体と剛体の接触拘束;
use super::body_static_contact::剛体と静的世界の接触拘束;
use super::contact_batches::接触拘束の二つのバッチ;
use super::mixing_rule::混合則;
use crate::xpbd::{コンプライアンス, 刻み幅};

/// 細分1本ぶんの接触拘束を積み上げる型。混合則を借りて保持し、積み終えたら2つのバッチになる。
pub struct 接触拘束のバッチの組み立て<'混合則の寿命> {
    混合則: &'混合則の寿命 混合則,
    接触のコンプライアンス: コンプライアンス,
    刻み幅: 刻み幅,
    剛体どうし: Vec<剛体と剛体の接触拘束>,
    剛体と静的世界: Vec<剛体と静的世界の接触拘束>,
}

impl<'混合則の寿命> 接触拘束のバッチの組み立て<'混合則の寿命> {
    /// 混合則と接触の柔らかさと細分の刻み幅を受けて、見込みの対の数ぶんの受け皿を確保する。
    /// コンプライアンス0が硬い接触であり、正の値は柔らかい接触である(判断12)。
    pub fn 生成する(
        混合則: &'混合則の寿命 混合則,
        接触のコンプライアンス: コンプライアンス,
        刻み幅: 刻み幅,
        見込みの接触の対の数: usize,
    ) -> Self {
        let 見込みの接触点の数 = 見込みの接触の対の数 * 接触点の上限;
        Self {
            混合則,
            接触のコンプライアンス,
            刻み幅,
            剛体どうし: Vec::with_capacity(見込みの接触点の数),
            剛体と静的世界: Vec::with_capacity(見込みの接触点の数),
        }
    }

    pub(super) fn 混合則(&self) -> &混合則 {
        self.混合則
    }

    pub(super) fn 接触のコンプライアンス(&self) -> コンプライアンス {
        self.接触のコンプライアンス
    }

    pub(super) fn 刻み幅(&self) -> 刻み幅 {
        self.刻み幅
    }

    pub(super) fn 剛体どうしへ積む(&mut self, 拘束: 剛体と剛体の接触拘束) {
        self.剛体どうし.push(拘束);
    }

    pub(super) fn 剛体と静的世界へ積む(&mut self, 拘束: 剛体と静的世界の接触拘束) {
        self.剛体と静的世界.push(拘束);
    }

    /// 積み終えた2つの一覧を細分が解くバッチにする。
    pub fn 二つのバッチを組み立てる(self) -> 接触拘束の二つのバッチ {
        接触拘束の二つのバッチ::積み終えた一覧から組む(self.剛体どうし, self.剛体と静的世界)
    }
}
