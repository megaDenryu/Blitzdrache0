//! 接触の射影に参加する1つの点(判断12・判断13・判断14)。姿勢自由度の参加者と、その参加者から見た点の組である。
//! 非貫通は接触点を、静止摩擦は錨を、速度段階は接触点をこの型で渡す。どれも「参加者と、その参加者から見た点」で
//! 一般化逆質量と腕と世界位置が決まるため、点の意味ごとに型を分けない。
//! 静的世界の接触相手をこの型で表すのは、参加者を「動かせない」として点そのものに置き局所点を零にすると、
//! 世界に固定された点と一般化逆質量0がそのまま得られるためである。これにより、剛体と剛体の接触拘束と
//! 剛体と静的世界の接触拘束が同じ射影の式を読める(2つのバッチは参加者Bの点の取り方だけが違う)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

use blitz_math::{ローカル, ワールド, 位置, 変位, 方向, 逆キログラム};

use crate::rigid_body::{姿勢, 配置};
use crate::rigid_xpbd::{姿勢自由度の参加者, 姿勢自由度の補正};
use crate::xpbd::ラグランジュ乗数;

/// 接触の射影の片側。参加者とその重心局所の点を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触の射影に参加する点 {
    参加者: 姿勢自由度の参加者,
    局所点: 変位<ローカル>,
}

impl 接触の射影に参加する点 {
    /// 剛体の側。細分の予測が作った配置を持つ参加者と、重心局所で持つ接触点または錨である。
    pub fn 剛体の局所点から生成する(参加者: 姿勢自由度の参加者, 局所点: 変位<ローカル>) -> Self {
        Self { 参加者, 局所点 }
    }

    /// 静的世界の接触相手の側。点そのものに動かせない参加者を置き、局所点を零にする。
    pub fn 静的世界の固定点から生成する(世界位置: 位置<ワールド>) -> Self {
        Self {
            参加者: 姿勢自由度の参加者::動かせない(配置::生成する(世界位置, 姿勢::恒等())),
            局所点: 変位::零(),
        }
    }

    pub(super) fn 動かせないか(&self) -> bool {
        self.参加者.動かせないか()
    }

    pub(super) fn 世界位置(&self) -> 位置<ワールド> {
        self.参加者.配置().局所点の世界位置(self.局所点)
    }

    pub(super) fn 腕(&self) -> 変位<ワールド> {
        self.参加者.配置().腕(self.局所点)
    }

    pub(super) fn 一般化逆質量(&self, 勾配の向き: 方向<ワールド>) -> 逆キログラム {
        self.参加者.一般化逆質量(self.腕(), 勾配の向き)
    }

    pub(super) fn 一般化逆質量の上界(&self, 勾配の向き: 方向<ワールド>) -> 逆キログラム {
        self.参加者.一般化逆質量の上界(self.腕(), 勾配の向き)
    }

    pub(super) fn 乗数を補正へ分配する(
        &self, 勾配の向き: 方向<ワールド>, 乗数の増分: ラグランジュ乗数
    ) -> 姿勢自由度の補正 {
        self.参加者.点に作用する乗数を補正へ分配する(self.腕(), 勾配の向き, 乗数の増分)
    }

    // 速度段階が衝撃を速度と角速度へ分配するために読む逆質量とワールドの逆慣性の持ち主。
    pub(super) fn 参加者(&self) -> &姿勢自由度の参加者 {
        &self.参加者
    }
}
