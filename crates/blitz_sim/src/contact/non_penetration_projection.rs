//! 非貫通の片側XPBD位置拘束の射影(判断12)。剛体と剛体の接触拘束と剛体と静的世界の接触拘束が読む唯一の式である。
//! 局面としてこの工程を係数の生成から分けているのは、係数が細分の開始で1度だけ導かれるのに対し、この射影は
//! 細分の中の反復ごとに呼ばれるためである。
//!   d = (p_B − p_A) · n が0以上なら読まず、負のとき C = d、Δλ = (−C − α̃λ) ÷ (w̃_A + w̃_B + α̃)
//!   λ_新 = λ + Δλ を [0, λ + 残りの長さ ÷ w̃の上界] へ切り詰め、Δλ ← λ_新 − λ。B へ +Δλ n、A へ −Δλ n の補正を分配する
//! 下限0は片側性(離れている物体を引き寄せない)である。上限は1細分で詰めてよい貫通の長さであり、その細分で詰めた
//! 相対補正の長さ max(Δλ, 0) w̃の上界 を状態が累計で持ち、残りの長さで増分を切り詰める(深い初期重なりの切り詰め)。
//! 長さと乗数の換算に線形化した w̃ でなくその上界を使うのは、姿勢の補正が正規化した有限回転として適用されるためである。
//! 腕の先が描く弦は1次の接線の変位と向きが違い、法線への射影は1次の値を上回りうる。上界 w + |(I⁻¹ (r × n)) × r| は
//! この実際の移動も上から抑えるため、細分に詰まる実測の分離の増分が形の最小の厚みを超えない(反証を検査に置いた)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

use blitz_math::{ワールド, 方向};

use super::non_penetration_coefficients::非貫通の一刻みの係数;
use super::non_penetration_participant::非貫通の参加点;
use super::non_penetration_result::非貫通の一回の射影の結果;
use super::non_penetration_substep_state::非貫通の一細分の解の状態;
use crate::xpbd::ラグランジュ乗数;

impl 非貫通の一刻みの係数 {
    /// 正典式の1回の反復。接触法線は第1の参加者から第2の参加者へ向かう向きである。
    pub fn 一回射影する(
        &self,
        a: 非貫通の参加点,
        b: 非貫通の参加点,
        接触法線: 方向<ワールド>,
        解の状態: 非貫通の一細分の解の状態,
    ) -> 非貫通の一回の射影の結果 {
        if a.動かせないか() && b.動かせないか() {
            return 非貫通の一回の射影の結果::両方が動かせない;
        }
        let 隔たり = (b.世界位置() - a.世界位置()).方向に沿う長さ(接触法線);
        if 隔たり.値() >= 0.0 {
            return 非貫通の一回の射影の結果::離れている;
        }
        let 有効逆質量 = a.一般化逆質量(接触法線) + b.一般化逆質量(接触法線);
        let 有効逆質量の上界 = a.一般化逆質量の上界(接触法線) + b.一般化逆質量の上界(接触法線);
        let 乗数 = 解の状態.法線のラグランジュ乗数();
        let 増分 = ラグランジュ乗数::長さを逆質量で割って生成する(
            (隔たり + 乗数 * self.刻み依存量()) * -1.0,
            有効逆質量 + self.刻み依存量(),
        );
        let 上限 = 乗数
            + ラグランジュ乗数::長さを逆質量で割って生成する(
                解の状態.残りの相対補正の長さ(self.一細分の補正の長さの上限()),
                有効逆質量の上界,
            );
        let 実際の増分 = (乗数 + 増分).区間へ収める(ラグランジュ乗数::零(), 上限) - 乗数;
        非貫通の一回の射影の結果::補正した {
            補正a: a.乗数を補正へ分配する(接触法線.逆を向く方向(), 実際の増分),
            補正b: b.乗数を補正へ分配する(接触法線, 実際の増分),
            更新後の解の状態: 解の状態.乗数の増分を足した状態(実際の増分, 有効逆質量の上界),
        }
    }
}
