//! 休止の閾値を細分の本数へ写す導出が、閾値の物理時間0.125秒へ本当に達する最小の本数を返すことの検査(判断18)。
//! 閾値を相対的に縮めて到達とみなす形の反証をここに置く。縮めると、10本で0.1249999秒しか経っていない刻み幅まで
//! 10本で休止する帯ができ、細分ごとに秒を積むのをやめて追い出したはずの数値誤差が時間契約へ戻る。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」

use blitz_math::秒;

use super::contact_thresholds::休止と判定する連続静穏の細分の本数;
use crate::xpbd::刻み幅;

const 閾値のちょうど十分の一の秒数: f32 = 0.0125; // 単精度では0.125の十分の一をわずかに上回る値へ丸められ、10本で閾値へ達する

fn 閾値の本数(細分の刻み幅の秒数: f32) -> u32 {
    let Ok(幅) = 刻み幅::生成する(秒::生成する(細分の刻み幅の秒数)) else {
        panic!("細分の刻み幅を作れない");
    };
    let Ok(本数) = 休止と判定する連続静穏の細分の本数(幅) else {
        panic!("休止の閾値を細分の本数へ写せない刻み幅である");
    };
    本数.本数()
}

#[test]
fn 十本で閾値へわずかに届かない刻み幅では本数が十一本になる() {
    let 届く刻み幅の秒数 = 閾値のちょうど十分の一の秒数;
    let 届かない刻み幅の秒数 = f32::from_bits(届く刻み幅の秒数.to_bits() - 1); // 単精度で1つ下の値であり、10本ぶんが0.125秒をわずかに下回る
    assert_eq!(閾値の本数(届く刻み幅の秒数), 10, "10本ぶんが0.125秒へ達する刻み幅で11本を要求している");
    assert_eq!(
        閾値の本数(届かない刻み幅の秒数),
        11,
        "10本ぶんが0.125秒へ届かない刻み幅を10本で休止させている(閾値を縮めて到達とみなしている)"
    );
}

#[test]
fn 本番の二つの細分数では余裕を足さずに正本の本数へ達する() {
    assert_eq!(閾値の本数(1.0 / 480.0), 60, "細分数8の刻み幅で60本が0.125秒へ達していない");
    assert_eq!(閾値の本数(1.0 / 960.0), 120, "細分数16の刻み幅で120本が0.125秒へ達していない");
}
