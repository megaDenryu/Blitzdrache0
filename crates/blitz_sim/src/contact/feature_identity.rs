//! 接触の特徴の識別: 1つの接触点が、触れ合う2つの形のどの特徴どうしで生まれたかの綴り(判断16)。
//! 衝突数学層は形の組ごとに別の型(直方体どうし・直方体と三角形)で綴りを返すため、剛体の側はそれを1つの列挙で受ける。
//! 1つにするのは、接触の履歴の鍵が(参加者2つ, 特徴の識別)の3つ組であり、参加者の組ごとの1つのバッチに両方の形の組が
//! 載るためである(剛体と静的世界のバッチには建物の直方体と地形の三角形の両方が来る)。判断10が禁じているのは
//! 参加する自由度を1つの列挙で指すことであり、この列挙は自由度でなく綴りを指す。
//! 全順序は導出であり、値の並びに意味は無い。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断16: 接触の履歴は参加者の組ごとに特徴の識別を鍵に全順序の併走で対応付け、暖機はしない」

use blitz_collision::contact_set::{直方体と三角形の接触の特徴の対, 直方体どうしの接触の特徴の対};

/// 接触点1つがどの特徴どうしで生まれたかの綴り。形の組の種類ごとに枝を持つ。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum 接触の特徴の識別 {
    /// 2つの直方体の面・辺・頂点の対で生まれた接触点。
    直方体どうし(直方体どうしの接触の特徴の対),
    /// 直方体と三角形の面・辺・頂点の対で生まれた接触点。
    直方体と三角形(直方体と三角形の接触の特徴の対),
}

impl From<直方体どうしの接触の特徴の対> for 接触の特徴の識別 {
    fn from(対: 直方体どうしの接触の特徴の対) -> Self {
        Self::直方体どうし(対)
    }
}

impl From<直方体と三角形の接触の特徴の対> for 接触の特徴の識別 {
    fn from(対: 直方体と三角形の接触の特徴の対) -> Self {
        Self::直方体と三角形(対)
    }
}
