//! 射影が返した補正を実際に配置へ適用して測る、法線方向の分離の増分の検査(判断12)。担当するのは、1細分に詰めてよい
//! 長さの上限が、線形化した補正の長さだけでなく、補正を適用した後の接触点の実際の移動に対しても効くことを固定することである。
//! 姿勢の補正は正規化した有限回転として適用されるため、腕の先が描く弦は1次の接線の変位と向きが違い、法線への射影は
//! 1次の値を上回りうる。上限は形の最小の厚み1回分であり無条件に無視できる大きさではないため、線形の帳簿を見る
//! `non_penetration_correction_tests` とは別に、ここでは配置へ適用した後の世界座標から増分を測り直す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

#![allow(clippy::unwrap_used)]

use blitz_math::{
    キログラム, キログラム平方メートル, クォータニオン, メートル, ローカル, ワールド, 位置, 変位, 逆キログラム
};

