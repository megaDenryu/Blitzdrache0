use super::contact_test_fixtures::{世界の位置を作る, 局所の変位を作る, 試験の刻み幅};
use super::non_penetration_fixture::{下向きの接触法線, 剛体と静的世界の基本の引数, 試験の形の最小の厚み};
use super::non_penetration_result::非貫通の一回の射影の結果;
use crate::rigid_body::{主慣性, 主慣性と主軸, 姿勢, 質量特性, 配置};
use crate::rigid_xpbd::{姿勢自由度の参加者, 姿勢自由度の補正};

const 深く重なった重心の高さ: f32 = -10.0; // 1細分の上限(厚み1メートル)より十分に深く、上限が必ず効く深さ
const 測る反復の回数: usize = 8;

/// 射影が返した補正を自分の配置へ適用しながら、接触点の世界位置を追う剛体。
struct 補正を配置へ適用して追う剛体 {
    配置: 配置,
    質量特性: 質量特性,
    局所接触点: 変位<ローカル>,
}

impl 補正を配置へ適用して追う剛体 {
    // 偏心した接触点と異方の主慣性を持つ剛体。局所接触点は重心から接触法線の向き(下)へも外れており、腕の先が描く弦の
    // 法線への射影が1次の接線の変位を上回る配置である。主慣性を3値とも変えるのは、補正の回転軸が主軸のどれとも揃わず、
    // ワールドの逆慣性そのものが反復のあいだに変わるようにするためである。
    fn 偏心した接触点と異方の主慣性で生成する() -> Self {
        let 主慣性 = 主慣性::生成する(
            キログラム平方メートル::生成する(1.0),
            キログラム平方メートル::生成する(2.0),
            キログラム平方メートル::生成する(2.5),
        );
        Self {
            配置: 配置::生成する(世界の位置を作る(0.0, 深く重なった重心の高さ, 0.0), 姿勢::恒等()),
            質量特性: 質量特性::生成する(
                キログラム::生成する(1.0).unwrap(),
                変位::零(),
                主慣性と主軸::生成する(主慣性, クォータニオン::軸が一致する回転()).unwrap(),
            )
            .unwrap(),
            局所接触点: 局所の変位を作る(2.0, -1.5, 0.8),
        }
    }

    fn 参加者(&self) -> 姿勢自由度の参加者 {
        姿勢自由度の参加者::動的(self.配置, &self.質量特性)
    }

    fn 接触点の一般化逆質量(&self) -> 逆キログラム {
        self.参加者().一般化逆質量(self.配置.腕(self.局所接触点), 下向きの接触法線())
    }

    // 静的世界の点から見た法線方向の隔たり d = (p_静 − p_剛)·n。負が貫通であり、増えることが分離である。
    fn 静的世界の点からの隔たり(&self, 静的世界の点: 位置<ワールド>) -> メートル {
        (静的世界の点 - self.配置.局所点の世界位置(self.局所接触点)).方向に沿う長さ(下向きの接触法線())
    }

    fn 補正を配置へ適用する(&mut self, 補正: 姿勢自由度の補正) {
        self.配置 = 補正.配置へ適用する(&self.配置);
    }
}

fn 剛体側の局所接触点を持つ拘束(局所接触点: 変位<ローカル>) -> 剛体と静的世界の接触拘束 {
    let 引数 = 剛体と静的世界の接触拘束の引数 {
        剛体側の局所接触点: 局所接触点,
        ..剛体と静的世界の基本の引数()
    };
    剛体と静的世界の接触拘束::引数と刻み幅から生成する(引数, 試験の刻み幅()).unwrap()
}

#[test]
fn 補正を配置へ適用して測った分離の増分の累計は形の最小の厚みを超えない() {
    let mut 剛体 = 補正を配置へ適用して追う剛体::偏心した接触点と異方の主慣性で生成する();
    let mut 拘束 = 剛体側の局所接触点を持つ拘束(剛体.局所接触点);
    let 静的世界の点 = 拘束.引数().静的世界側の接触点;
    let 最初の一般化逆質量 = 剛体.接触点の一般化逆質量();
    let mut 正の分離の増分の累計 = メートル::生成する(0.0);
    for _ in 0..測る反復の回数 {
        let 前の隔たり = 剛体.静的世界の点からの隔たり(静的世界の点);
        let 結果 = 拘束.一回射影する(&剛体.参加者());
        let 非貫通の一回の射影の結果::補正した { 補正a, .. } = 結果 else {
            panic!("深く貫通しているのに補正しなかった: {結果:?}");
        };
        剛体.補正を配置へ適用する(補正a);
        let 増分 = 剛体.静的世界の点からの隔たり(静的世界の点) - 前の隔たり;
        if 増分.値() > 0.0 {
            正の分離の増分の累計 = 正の分離の増分の累計 + 増分;
        }
    }
    let 有効逆質量の変化 = (剛体.接触点の一般化逆質量().値() - 最初の一般化逆質量.値()).abs();
    assert!(有効逆質量の変化 > 0.1, "反復のあいだに有効逆質量が変わっていない材料では反証にならない");
    assert!(
        正の分離の増分の累計.値() <= 試験の形の最小の厚み,
        "実測の分離の増分の累計{}メートルが形の最小の厚み{試験の形の最小の厚み}メートルを超えた",
        正の分離の増分の累計.値()
    );
}
