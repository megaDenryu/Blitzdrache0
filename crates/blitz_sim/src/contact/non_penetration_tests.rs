//! 非貫通の片側性の試験(判断12)。担当するのは3つの性質を固定することである。法線方向に離れている接触では補正も
//! 乗数の変化も起こらないこと、柔らかい接触で乗数の増分が負になっても乗数が0より下へ行かないこと、
//! 両方の参加者が動かせないときに理由の枝を返すことである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

#![allow(clippy::unwrap_used)]

use super::body_body_contact::剛体と剛体の接触拘束;
use super::body_body_contact_parameters::剛体と剛体の接触拘束の引数;
use super::contact_test_fixtures::試験の刻み幅;
use super::non_penetration_fixture::{剛体どうしの基本の引数, 動かせない参加者, 解き方を作る, 高さの参加者};
use super::non_penetration_result::非貫通の一回の射影の結果;
use crate::xpbd::ラグランジュ乗数;

// 接触法線は下向きであり、隔たり d = (p_B − p_A)·n = y_A − y_B である。剛体aを剛体bより低く置くと貫通になる。
fn 拘束を作る(引数: 剛体と剛体の接触拘束の引数) -> 剛体と剛体の接触拘束 {
    剛体と剛体の接触拘束::引数と刻み幅から生成する(引数, 試験の刻み幅()).unwrap()
}

#[test]
fn 離れている接触では補正も乗数の変化も起きない() {
    let mut 拘束 = 拘束を作る(剛体どうしの基本の引数());
    let 結果 = 拘束.一回射影する(&高さの参加者(1.0), &高さの参加者(-1.0));
    assert_eq!(結果, 非貫通の一回の射影の結果::離れている);
    assert_eq!(拘束.法線のラグランジュ乗数(), ラグランジュ乗数::零());
}

#[test]
fn 貫通している接触では乗数が正になり両方が押し戻される() {
    let mut 拘束 = 拘束を作る(剛体どうしの基本の引数());
    let 結果 = 拘束.一回射影する(&高さの参加者(-0.05), &高さの参加者(0.0));
    let 非貫通の一回の射影の結果::補正した { 補正a, 補正b, .. } = 結果 else {
        panic!("貫通しているのに補正しなかった: {結果:?}");
    };
    assert!(拘束.法線のラグランジュ乗数() > ラグランジュ乗数::零());
    assert!(補正a.並進().y().値() > 0.0);
    assert!(補正b.並進().y().値() < 0.0);
}

#[test]
fn 柔らかい接触で乗数の増分が負になっても乗数は0以上に留まる() {
    let mut 拘束 = 拘束を作る(剛体と剛体の接触拘束の引数 {
        解き方: 解き方を作る(1.0),
        ..剛体どうしの基本の引数()
    });
    拘束.一回射影する(&高さの参加者(-0.5), &高さの参加者(0.0));
    let 深い貫通の乗数 = 拘束.法線のラグランジュ乗数();
    assert!(深い貫通の乗数 > ラグランジュ乗数::零());
    for _ in 0..50 {
        拘束.一回射影する(&高さの参加者(-1.0e-6), &高さの参加者(0.0));
        assert!(拘束.法線のラグランジュ乗数() >= ラグランジュ乗数::零());
    }
    assert!(拘束.法線のラグランジュ乗数() < 深い貫通の乗数);
}

#[test]
fn 両方が動かせない接触は理由の枝を返す() {
    let mut 拘束 = 拘束を作る(剛体どうしの基本の引数());
    let 結果 = 拘束.一回射影する(&動かせない参加者(-0.05), &動かせない参加者(0.0));
    assert_eq!(結果, 非貫通の一回の射影の結果::両方が動かせない);
    assert_eq!(拘束.法線のラグランジュ乗数(), ラグランジュ乗数::零());
}
