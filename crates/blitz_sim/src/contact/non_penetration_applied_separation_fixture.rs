//! 射影が返した補正を実際に配置へ適用して測る試験が共有する材料(判断12)。担当するのは、自分の配置を持ち歩いて
//! 接触点の世界位置を追う剛体と、その剛体の局所接触点と解き方を持つ剛体と静的世界の接触拘束を作ることである。
//! 剛体が配置を持つのは、姿勢の補正が正規化した有限回転として適用されるため、分離の増分を線形の帳簿でなく
//! 適用後の世界座標から測り直す必要があるからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{
    キログラム, キログラム平方メートル, クォータニオン, メートル, ローカル, ワールド, 位置, 変位, 逆キログラム
};

use super::body_static_contact::剛体と静的世界の接触拘束;
use super::body_static_contact_parameters::剛体と静的世界の接触拘束の引数;
use super::contact_test_fixtures::{世界の位置を作る, 局所の変位を作る, 試験の刻み幅};
use super::non_penetration_coefficients::非貫通の解き方;
use super::non_penetration_fixture::{下向きの接触法線, 剛体と静的世界の基本の引数};
use crate::rigid_body::{主慣性, 主慣性と主軸, 姿勢, 質量特性, 配置};
use crate::rigid_xpbd::{姿勢自由度の参加者, 姿勢自由度の補正};

const 深く重なった重心の高さ: f32 = -10.0; // 1細分の上限(厚み1メートル)より十分に深く、上限が必ず効く深さ

/// 射影が返した補正を自分の配置へ適用しながら、接触点の世界位置を追う剛体。
pub(super) struct 補正を配置へ適用して追う剛体 {
    配置: 配置,
    質量特性: 質量特性,
    局所接触点: 変位<ローカル>,
}

impl 補正を配置へ適用して追う剛体 {
    // 偏心した接触点と異方の主慣性を持つ剛体。局所接触点は重心から接触法線の向き(下)へも外れており、腕の先が描く弦の
    // 法線への射影が1次の接線の変位を上回る配置である。主慣性を3値とも変えるのは、補正の回転軸が主軸のどれとも揃わず、
    // ワールドの逆慣性そのものが反復のあいだに変わるようにするためである。
    pub(super) fn 偏心した接触点と異方の主慣性で生成する() -> Self {
        let 主慣性 = 主慣性::生成する(
            キログラム平方メートル::生成する(1.0),
            キログラム平方メートル::生成する(2.0),
            キログラム平方メートル::生成する(2.5),
        );
        Self {
            配置: 配置::生成する(世界の位置を作る(0.0, 深く重なった重心の高さ, 0.0), 姿勢::恒等()),
            質量特性: 質量特性::生成する(
                キログラム::生成する(1.0).unwrap(),
                変位::零(),
                主慣性と主軸::生成する(主慣性, クォータニオン::軸が一致する回転()).unwrap(),
            )
            .unwrap(),
            局所接触点: 局所の変位を作る(2.0, -1.5, 0.8),
        }
    }

    pub(super) fn 局所接触点(&self) -> 変位<ローカル> {
        self.局所接触点
    }

    pub(super) fn 参加者(&self) -> 姿勢自由度の参加者 {
        姿勢自由度の参加者::動的(self.配置, &self.質量特性)
    }

    pub(super) fn 接触点の一般化逆質量(&self) -> 逆キログラム {
        self.参加者().一般化逆質量(self.配置.腕(self.局所接触点), 下向きの接触法線())
    }

    // 静的世界の点から見た法線方向の隔たり d = (p_静 − p_剛)·n。負が貫通であり、増えることが分離である。
    pub(super) fn 静的世界の点からの隔たり(&self, 静的世界の点: 位置<ワールド>) -> メートル {
        (静的世界の点 - self.配置.局所点の世界位置(self.局所接触点)).方向に沿う長さ(下向きの接触法線())
    }

    pub(super) fn 補正を配置へ適用する(&mut self, 補正: 姿勢自由度の補正) {
        self.配置 = 補正.配置へ適用する(&self.配置);
    }

    // 同じ細分の中で他の拘束がこの剛体を動かす分を、隔たりが目標の値になる並進で表す。接触法線が真下を向くため、
    // 重心を法線の向きへ動かした長さがそのまま隔たりの変化になる。
    pub(super) fn 他の拘束が隔たりを目標へ動かす(
        &mut self, 静的世界の点: 位置<ワールド>, 目標の隔たり: メートル
    ) {
        let 差 = 目標の隔たり - self.静的世界の点からの隔たり(静的世界の点);
        self.配置 = self.配置.並進で動かす(変位::方向へ進む(下向きの接触法線().逆を向く方向(), 差));
    }
}

/// 剛体の側の局所接触点と解き方だけを差し替えた、剛体と静的世界の接触拘束。
pub(super) fn 局所接触点と解き方を持つ拘束(
    局所接触点: 変位<ローカル>, 解き方: 非貫通の解き方
) -> 剛体と静的世界の接触拘束 {
    let 引数 = 剛体と静的世界の接触拘束の引数 {
        剛体側の局所接触点: 局所接触点,
        解き方,
        ..剛体と静的世界の基本の引数()
    };
    剛体と静的世界の接触拘束::引数と刻み幅から生成する(引数, 試験の刻み幅()).unwrap()
}
