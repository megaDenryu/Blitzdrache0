//! 接触物性の生成と参照が拒んだ入力(判断15)。摩擦と反発の値域の破れ、材質の表面物性の未登録、同じ鍵の二重登録の3つを述べる。
//! 未登録の材質を黙って既定の物性で埋めないため、参照の失敗もここへ入れる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断15: 接触物性は両表面の物性から混合則で決め、既定則と材質対の上書き表を持つ」

use thiserror::Error;

/// 接触物性の生成と、混合則の登録と参照が拒んだ入力。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 接触物性エラー {
    /// 摩擦係数が負であるか有限でない。
    #[error("摩擦係数は0以上の有限値でなければならない(指定値: {値})")]
    摩擦係数が値域の外 { 値: f32 },
    /// 動摩擦係数が静止摩擦係数を超えている。滑り出した後の抵抗が保持の限界より強い状態は物理的に意味を持たない。
    #[error("動摩擦係数は静止摩擦係数以下でなければならない(静止: {静止摩擦係数}、動: {動摩擦係数})")]
    動摩擦係数が静止摩擦係数を超えている { 静止摩擦係数: f32, 動摩擦係数: f32 },
    /// 反発係数が0から1の外であるか有限でない。
    #[error("反発係数は0以上1以下の有限値でなければならない(指定値: {値})")]
    反発係数が値域の外 { 値: f32 },
    /// 材質の識別子に対応する表面物性が混合則へ登録されていない。
    #[error("材質の表面物性が登録されていない(材質の識別子: {材質の識別子})")]
    材質の表面物性が未登録 { 材質の識別子: u32 },
    /// 同じ材質の識別子へ表面物性を2回登録した。どちらが正しいかを組み立てが決められない。
    #[error("同じ材質の識別子へ表面物性を二重に登録した(材質の識別子: {材質の識別子})")]
    表面物性の二重登録 { 材質の識別子: u32 },
    /// 同じ材質の対へ上書きの接触物性を2回登録した。対は順序を正規化するため、順を入れ替えた登録も二重登録である。
    #[error("同じ材質の対へ上書きを二重に登録した(材質の識別子: {小さい方}と{大きい方})")]
    材質対の上書きの二重登録 { 小さい方: u32, 大きい方: u32 },
}
