//! 剛体と剛体の接触点1つの非貫通拘束(判断11)。細分の開始で接触点集合から生成し、細分の終了で捨てる一時の値であり、
//! 刻みを跨いで持つ口を持たない(刻みを跨ぐのは判断16の履歴である)。
//! 静的な引数と、細分の刻み幅で導いた係数と、一細分内の状態であるラグランジュ乗数の3つに分けて持つ(XPBD共通拘束基盤の判断4)。
//! 乗数は細分の開始で0から始め、前の細分の値から始める暖機はしない(判断16)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use super::body_body_contact_parameters::剛体と剛体の接触拘束の引数;
use super::non_penetration_coefficients::非貫通の一刻みの係数;
use super::non_penetration_participant::非貫通の参加点;
use super::non_penetration_result::非貫通の一回の射影の結果;
use crate::rigid_xpbd::姿勢自由度の参加者;
use crate::xpbd::{コンプライアンスエラー, ラグランジュ乗数, 刻み幅};

/// 剛体と剛体の接触拘束のバッチの1件。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 剛体と剛体の接触拘束 {
    引数: 剛体と剛体の接触拘束の引数,
    一刻みの係数: 非貫通の一刻みの係数,
    法線のラグランジュ乗数: ラグランジュ乗数,
}

impl 剛体と剛体の接触拘束 {
    /// 静的な引数と細分1本の刻み幅から作る。コンプライアンスの刻み依存量をここで1度だけ導く。
    pub fn 引数と刻み幅から生成する(
        引数: 剛体と剛体の接触拘束の引数, 刻み幅: 刻み幅
    ) -> Result<Self, コンプライアンスエラー> {
        Ok(Self {
            一刻みの係数: 引数.解き方.刻み幅で解く係数を導く(刻み幅)?,
            引数,
            法線のラグランジュ乗数: ラグランジュ乗数::零(),
        })
    }

    /// 細分の間に変わらない値。接触の履歴の鍵・反復の順序・摩擦と速度段階がここから読む。
    pub fn 引数(&self) -> &剛体と剛体の接触拘束の引数 {
        &self.引数
    }

    /// この細分で累積した法線方向のラグランジュ乗数。摩擦のクーロン円錐と速度段階がこれを読む。
    pub fn 法線のラグランジュ乗数(&self) -> ラグランジュ乗数 {
        self.法線のラグランジュ乗数
    }

    /// 非貫通を一回射影し、乗数を更新する。呼び出し側は返った2つの補正を各剛体の予測の状態へ適用する。
    pub fn 一回射影する(
        &mut self, 剛体a: &姿勢自由度の参加者, 剛体b: &姿勢自由度の参加者
    ) -> 非貫通の一回の射影の結果 {
        let 結果 = self.一刻みの係数.一回射影する(
            非貫通の参加点::剛体の局所点から生成する(*剛体a, self.引数.局所接触点a),
            非貫通の参加点::剛体の局所点から生成する(*剛体b, self.引数.局所接触点b),
            self.引数.接触法線,
            self.法線のラグランジュ乗数,
        );
        if let 非貫通の一回の射影の結果::補正した {
            更新後のラグランジュ乗数,
        ..
        } = 結果
        {
            self.法線のラグランジュ乗数 = 更新後のラグランジュ乗数;
        }
        結果
    }
}
