//! 剛体と剛体の接触拘束のうち、錨に触れる操作(判断13・判断16)。履歴との受け渡しと静止摩擦の射影である。
//! この2つを1つのモジュールにしているのは、どちらも錨を読み書きする唯一の経路であり、分けると錨の書き換えの口が
//! 2つのモジュールへ開くためである。細分の中で錨が変わるのは接触点集合が円錐を超えた反復だけであり、その置き直しもここが行う。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::super::contact_projection_row::接触の射影に参加する点;
use super::super::history::剛体どうしの接触の鍵;
use super::super::history::接触の継続の記録;
use super::super::history::{剛体どうしの接触の履歴の項目, 剛体どうしの接触の継続の記録};
use super::super::normal_tangential_system::接触点集合の法線と接線の連立;
use super::super::static_friction::接線のラグランジュ乗数;
use super::super::static_friction::静止摩擦の一回の仮の射影の結果;
use super::super::static_friction::静止摩擦の連立へ点を入れた結果;
use super::super::static_friction::静止摩擦の錨;
use super::剛体と剛体の接触拘束;
use blitz_math::{ローカル, 変位};

use crate::rigid_body::配置;
use crate::rigid_xpbd::姿勢自由度の参加者;

impl 剛体と剛体の接触拘束 {
    /// 接触の履歴がこの接触点を指す鍵。2つの剛体の識別子は接触点集合を積む工程が昇順へ揃えている。
    pub fn 履歴の鍵(&self) -> 剛体どうしの接触の鍵 {
        剛体どうしの接触の鍵::生成する(self.引数.剛体a, self.引数.剛体b, self.引数.特徴の識別)
    }

    /// 履歴の併走へ持ち込む項目。記録はこの細分の接触点に置いた錨であり、継続した接触は次で置き直す。
    pub fn 併走へ持ち込む履歴の項目(&self) -> 剛体どうしの接触の履歴の項目 {
        剛体どうしの接触の履歴の項目::生成する(self.履歴の鍵(), self.この細分の記録())
    }

    /// 併走が継続と判定した接触点へ、前の細分の錨を置き直す。
    pub fn 継続の記録を引き継ぐ(&mut self, 引き継いだ記録: 剛体どうしの接触の継続の記録) {
        self.錨 = 引き継いだ記録.錨();
    }

    /// 併走が開始と判定した接触点の錨を、細分の予測の前の2つの配置で重なっていた点へ置き直す。
    /// 生成のときの錨は予測の後の配置の接触点であり、その細分の錨からの接線変位が零になる。位置の静止摩擦が
    /// その細分で1度も効かず、2つの剛体は細分1本ぶんの接線の滑りを持ったまま次の細分へ入る。次の細分は
    /// 2細分ぶんの滑りを1度に戻すことになり、要る接線の乗数が跳ねて円錐を超える。
    pub fn 開始した接触の錨を予測の前の配置へ置く(
        &mut self, 予測の前のaの配置: &配置, 予測の前のbの配置: &配置
    ) {
        self.錨 = 静止摩擦の錨::生成する(
            self.引数.局所接触点a,
            第2の剛体から見た錨の点(self.引数.局所接触点a, 予測の前のaの配置, 予測の前のbの配置),
        );
        self.静止摩擦の解の状態 = self.静止摩擦の解の状態.錨を置き直した状態();
    }

    /// 細分の終わりに履歴へ書き戻す項目。錨はこの細分の終わりの値であり、法線はこの細分の接触法線である。
    pub fn 細分の終わりの履歴の項目(&self) -> 剛体どうしの接触の履歴の項目 {
        剛体どうしの接触の履歴の項目::生成する(self.履歴の鍵(), self.この細分の記録())
    }

    /// 法線と接線の連立へこの点の接線の1行を積む。乗数の増分は接触点集合の連立を解いて決まるため、ここでは状態を変えない。
    /// 法線反力の有無をここで見ないのは、混合の連立が法線の乗数を接線と同時に決めるためである。
    pub fn 法線と接線の連立へ接線の一行を積む(
        &self,
        点の番号: usize,
        連立: &mut 接触点集合の法線と接線の連立,
        剛体a: &姿勢自由度の参加者,
        剛体b: &姿勢自由度の参加者,
    ) -> 静止摩擦の連立へ点を入れた結果 {
        self.静止摩擦の解の状態.連立へ接線の一行を積む(
            点の番号,
            連立,
            接触の射影に参加する点::剛体の局所点から生成する(*剛体a, self.錨.第1の参加者の重心局所点()),
            接触の射影に参加する点::剛体の局所点から生成する(*剛体b, self.錨.第2の参加者から見た点()),
            self.引数.接触法線,
        )
    }

    /// 法線反力が無くなった接触点の接線の乗数を零へ戻す。集合が円錐を超えた反復でも確定する有効集合の更新である。
    pub fn 静止摩擦の接線の乗数を零へ解放する(&mut self) {
        self.静止摩擦の解の状態 = self.静止摩擦の解の状態.接線の乗数を零へ解放した状態();
    }

    /// 静止摩擦を一回仮に射影する。確定するかどうかは接触点集合の円錐の判定が決めるため、ここでは状態を変えない。
    pub fn 静止摩擦を一回仮に射影する(
        &self,
        剛体a: &姿勢自由度の参加者,
        剛体b: &姿勢自由度の参加者,
    ) -> 静止摩擦の一回の仮の射影の結果 {
        if !self.非貫通の解の状態.法線反力が在るか() {
            return 静止摩擦の一回の仮の射影の結果::法線反力が無い;
        }
        self.静止摩擦の解の状態.一回仮に射影する(
            接触の射影に参加する点::剛体の局所点から生成する(*剛体a, self.錨.第1の参加者の重心局所点()),
            接触の射影に参加する点::剛体の局所点から生成する(*剛体b, self.錨.第2の参加者から見た点()),
            self.引数.接触法線,
        )
    }

    /// 接触点集合の判定が円錐の内側と決めたときに、仮に進めた接線の乗数を確定する。錨は動かない。
    pub fn 静止摩擦の仮の乗数を確定する(&mut self, 進めた接線の乗数: 接線のラグランジュ乗数) {
        self.静止摩擦の解の状態 = self.静止摩擦の解の状態.仮の乗数を確定した状態(進めた接線の乗数);
    }

    /// 接触点集合が円錐を超えたときの後始末。滑走中と印し、錨をいまの2つの配置で重なっている点へ置き直す。
    /// 置き直す先を引数の局所接触点にしてはならない。それは予測の直後の接触点であり、この細分の反復で積んだ補正の
    /// ぶんだけ後ろにある。次の細分がその遅れと自分の滑りを合わせて戻すことになり、要る接線の乗数が円錐を再び超えて、
    /// 一度滑り出した接触点集合が二度と保持へ戻れなくなる。
    pub fn 接触点集合が滑走中になったと印す(&mut self, 剛体a: &姿勢自由度の参加者, 剛体b: &姿勢自由度の参加者) {
        self.静止摩擦の解の状態 = self.静止摩擦の解の状態.接触点集合が滑走中になった状態().錨を置き直した状態();
        self.錨 = 静止摩擦の錨::生成する(
            self.引数.局所接触点a,
            第2の剛体から見た錨の点(self.引数.局所接触点a, 剛体a.配置(), 剛体b.配置()),
        );
    }

    fn この細分の記録(&self) -> 剛体どうしの接触の継続の記録 {
        接触の継続の記録::生成する(self.錨, self.引数.接触法線)
    }
}

// 第1の剛体の接触点が、その2つの配置のもとで第2の剛体のどの重心局所点と重なるかを求める。
// 錨は2つの局所点の組であり、その2点が世界で重なっている状態を「滑っていない」と定める。
fn 第2の剛体から見た錨の点(
    第1の剛体の局所接触点: 変位<ローカル>, aの配置: &配置, bの配置: &配置
) -> 変位<ローカル> {
    bの配置.世界位置を重心局所へ写す(aの配置.局所点の世界位置(第1の剛体の局所接触点))
}
