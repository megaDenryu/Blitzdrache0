//! 剛体と剛体の接触拘束のうち、錨に触れる操作(判断13・判断16)。履歴との受け渡しと静止摩擦の射影である。
//! この2つを1つのモジュールにしているのは、どちらも錨を読み書きする唯一の経路であり、分けると錨の書き換えの口が
//! 2つのモジュールへ開くためである。細分の中で錨が変わるのはクーロン円錐を超えた反復だけであり、その置き直しもここが行う。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

use super::super::contact_projection_participant::接触の射影に参加する点;
use super::super::history::剛体どうしの接触の鍵;
use super::super::history::接触の継続の記録;
use super::super::history::{剛体どうしの接触の履歴の項目, 剛体どうしの接触の継続の記録};
use super::super::static_friction::静止摩擦の一回の射影の結果;
use super::super::static_friction::静止摩擦の錨;
use super::剛体と剛体の接触拘束;
use crate::rigid_xpbd::姿勢自由度の参加者;

impl 剛体と剛体の接触拘束 {
    /// 接触の履歴がこの接触点を指す鍵。2つの剛体の識別子は鍵の生成が昇順へ正規化する。
    pub fn 履歴の鍵(&self) -> 剛体どうしの接触の鍵 {
        剛体どうしの接触の鍵::生成する(self.引数.剛体a, self.引数.剛体b, self.引数.特徴の識別)
    }

    /// 履歴の併走へ持ち込む項目。記録はこの細分の接触点に置いた錨であり、継続した接触は次で置き直す。
    pub fn 併走へ持ち込む履歴の項目(&self) -> 剛体どうしの接触の履歴の項目 {
        剛体どうしの接触の履歴の項目::生成する(self.履歴の鍵(), self.この細分の記録())
    }

    /// 併走が継続と判定した接触点へ、前の細分の錨を置き直す。開始の接触点には生成時の錨がそのまま残る。
    pub fn 継続の記録を引き継ぐ(&mut self, 引き継いだ記録: 剛体どうしの接触の継続の記録) {
        self.錨 = 引き継いだ記録.錨();
    }

    /// 細分の終わりに履歴へ書き戻す項目。錨はこの細分の終わりの値であり、法線はこの細分の接触法線である。
    pub fn 細分の終わりの履歴の項目(&self) -> 剛体どうしの接触の履歴の項目 {
        剛体どうしの接触の履歴の項目::生成する(self.履歴の鍵(), self.この細分の記録())
    }

    /// 静止摩擦を一回射影する。円錐を超えた反復では補正を返さず、錨をこの細分の接触点へ置き直して滑走中と印す。
    pub fn 静止摩擦を一回射影する(
        &mut self,
        剛体a: &姿勢自由度の参加者,
        剛体b: &姿勢自由度の参加者,
    ) -> 静止摩擦の一回の射影の結果 {
        if !self.非貫通の解の状態.この細分で押し戻したか() {
            return 静止摩擦の一回の射影の結果::法線反力が無い;
        }
        let 結果 = self.静止摩擦の解の状態.一回射影する(
            接触の射影に参加する点::剛体の局所点から生成する(*剛体a, self.錨.第1の参加者の重心局所点()),
            接触の射影に参加する点::剛体の局所点から生成する(*剛体b, self.錨.第2の参加者から見た点()),
            self.引数.接触法線,
            self.引数.接触物性,
            self.非貫通の解の状態.法線のラグランジュ乗数(),
        );
        match 結果 {
            静止摩擦の一回の射影の結果::円錐の内側で保持した {
                更新後の解の状態, ..
            } => {
                self.静止摩擦の解の状態 = 更新後の解の状態;
            }
            静止摩擦の一回の射影の結果::円錐を超えて滑走中になった { 更新後の解の状態 } => {
                self.静止摩擦の解の状態 = 更新後の解の状態;
                self.錨 = 静止摩擦の錨::生成する(self.引数.局所接触点a, self.引数.局所接触点b);
            }
            静止摩擦の一回の射影の結果::既にこの細分で滑走中
            | 静止摩擦の一回の射影の結果::接線変位が零
            | 静止摩擦の一回の射影の結果::法線反力が無い
            | 静止摩擦の一回の射影の結果::両方が動かせない => {}
        }
        結果
    }

    fn この細分の記録(&self) -> 剛体どうしの接触の継続の記録 {
        接触の継続の記録::生成する(self.錨, self.引数.接触法線)
    }
}
