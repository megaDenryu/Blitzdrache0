//! 剛体と剛体の接触拘束のうち、持ち越す接線の残差に触れる操作(判断24)。細分の終わりに残差を測ることと、
//! その残差がこの細分で動いた量を仮の補正の連立へ積むことの2つである。
//! 錨に触れる操作(`history_and_friction`)から分けているのは、あちらが細分の反復のあいだ錨を読み書きする局面で
//! あるのに対し、こちらが反復を終えた確定の配置で1度だけ測る局面だからである。触れる状態も、あちらが錨と乗数、
//! こちらが持ち越しだけである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

use blitz_math::{ワールド, 変位};

use super::super::contact_projection_row::接触の射影に参加する点;
use super::super::static_friction::{持ち越す接線の残差, 残差の変化を打ち消す仮の補正の連立};
use super::剛体と剛体の接触拘束;
use crate::rigid_xpbd::姿勢自由度の参加者;

impl 剛体と剛体の接触拘束 {
    /// 反復を終えた2つの配置で、錨からの接線変位を測って細分の終わりの残差として書く(判断24)。
    /// 滑走中の集合と法線反力が無い点は残差を持たない。その細分にはこの点の静止摩擦の行が無く、
    /// 「閉じるべきだった変位」も無いためである。
    pub fn 細分の終わりの接線の残差を測る(&mut self, 剛体a: &姿勢自由度の参加者, 剛体b: &姿勢自由度の参加者) {
        let 測った残差 = if self.静止摩擦の解の状態.滑走中か() || !self.非貫通の解の状態.法線反力が在るか() {
            持ち越す接線の残差::無し
        } else {
            持ち越す接線の残差::測った変位から生成する(self.錨からの接線変位(剛体a, 剛体b))
        };
        self.接線の残差の持ち越し = self.接線の残差の持ち越し.細分の終わりに測った状態(測った残差);
    }

    /// この点の残差がこの細分で動いた量を、仮の補正の連立へ1行として積む(判断24)。
    /// 積む錨の参加点は、細分の反復を終えた確定の2つの配置から作る。
    pub fn 残差の変化を仮の補正の連立へ積む(
        &self,
        連立: &mut 残差の変化を打ち消す仮の補正の連立,
        剛体a: &姿勢自由度の参加者,
        剛体b: &姿勢自由度の参加者,
    ) {
        let Some(残差の変化) = self.接線の残差の持ち越し.細分のあいだの残差の変化() else {
            return;
        };
        連立.残差の変化を一行として積む(self.錨の第1の参加点(剛体a), self.錨の第2の参加点(剛体b), 残差の変化);
    }

    // 錨の2つの世界位置の差から法線の成分を除いた接線変位 Δ_t。判断13の行が読む量と同じ式である。
    fn 錨からの接線変位(&self, 剛体a: &姿勢自由度の参加者, 剛体b: &姿勢自由度の参加者) -> 変位<ワールド> {
        (self.錨の第1の参加点(剛体a).世界位置() - self.錨の第2の参加点(剛体b).世界位置()).方向の成分を除く(self.引数.接触法線)
    }

    fn 錨の第1の参加点(&self, 剛体a: &姿勢自由度の参加者) -> 接触の射影に参加する点 {
        接触の射影に参加する点::剛体の局所点から生成する(*剛体a, self.錨.第1の参加者の重心局所点())
    }

    fn 錨の第2の参加点(&self, 剛体b: &姿勢自由度の参加者) -> 接触の射影に参加する点 {
        接触の射影に参加する点::剛体の局所点から生成する(*剛体b, self.錨.第2の参加者から見た点())
    }
}
