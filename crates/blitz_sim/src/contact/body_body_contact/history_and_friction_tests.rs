fn 局所点(x: f32) -> 変位<ローカル> {
    変位::成分から生成する(メートル::生成する(x), メートル::生成する(0.0), メートル::生成する(0.0))
}

fn 拘束を作る(引数: 剛体と剛体の接触拘束の引数) -> 剛体と剛体の接触拘束 {
    剛体と剛体の接触拘束::引数と刻み幅から生成する(引数, 試験の刻み幅()).unwrap()
}

#[test]
fn 履歴の鍵は二つの剛体の識別子を昇順へ正規化する() {
    let 基本 = 剛体どうしの基本の引数();
    let 逆順 = 剛体と剛体の接触拘束の引数 {
        剛体a: 基本.剛体b,
        剛体b: 基本.剛体a,
        ..基本
    };
    assert_eq!(拘束を作る(基本).履歴の鍵(), 拘束を作る(逆順).履歴の鍵());
    assert!(基本.剛体a != 基本.剛体b, "試験の材料が同じ剛体を指している");
}

#[test]
fn 押し戻していない接触点の静止摩擦は法線反力が無いを返す() {
    let 拘束 = 拘束を作る(剛体どうしの基本の引数());
    assert_eq!(
        拘束.静止摩擦を一回仮に射影する(&高さの参加者(0.0), &高さの参加者(-1.0)),
        静止摩擦の一回の仮の射影の結果::法線反力が無い
    );
}

#[test]
fn 押し戻した接触点の静止摩擦は法線反力が無いを返さない() {
    let mut 拘束 = 拘束を作る(剛体どうしの基本の引数());
    let (剛体a, 剛体b) = (高さの参加者(0.0), 高さの参加者(0.1));
    assert!(matches!(拘束.一回射影する(&剛体a, &剛体b), 非貫通の一回の射影の結果::補正した { .. }));
    assert!(拘束.法線反力が在るか());
    assert_ne!(
        拘束.静止摩擦を一回仮に射影する(&剛体a, &剛体b),
        静止摩擦の一回の仮の射影の結果::法線反力が無い
    );
}

#[test]
fn 継続の記録を引き継ぐと細分の終わりの項目にその錨が載る() {
    let mut 拘束 = 拘束を作る(剛体どうしの基本の引数());
    let 引き継ぐ錨 = 静止摩擦の錨::生成する(局所点(0.3), 局所点(-0.4));
    let 記録 = 接触の継続の記録::生成する(引き継ぐ錨, 拘束.引数().接触法線, 持ち越す接線の残差::無し);
    拘束.継続の記録を引き継ぐ(記録);
    assert_eq!(拘束.細分の終わりの履歴の項目().記録().錨(), 引き継ぐ錨);
    assert_eq!(拘束.細分の終わりの履歴の項目().鍵(), 拘束.履歴の鍵());
}

#[test]
fn 速度段階へ渡す参加点と条件は拘束の引数と解の状態のとおりに組まれる() {
    let mut 拘束 = 拘束を作る(剛体どうしの基本の引数());
    let (剛体a, 剛体b) = (高さの参加者(0.0), 高さの参加者(0.1));
    拘束.一回射影する(&剛体a, &剛体b);
    let 法線相対速度 = メートル毎秒::生成する(-2.0);
    let 条件 = 拘束.速度段階の条件を組む(法線相対速度);
    assert_eq!(条件.接触法線(), 拘束.引数().接触法線);
    assert_eq!(条件.法線のラグランジュ乗数(), 拘束.法線のラグランジュ乗数());
    assert_eq!(条件.予測の前の法線相対速度(), 法線相対速度);
    assert_eq!(条件.滑走中か(), 拘束.静止摩擦の解の状態().滑走中か());
    let 静止した運動状態 = 運動状態::静止();
    assert_eq!(
        接触点の法線の相対速度を求める(
            拘束.速度段階の剛体aの参加点(&剛体a, 静止した運動状態),
            拘束.速度段階の剛体bの参加点(&剛体b, 静止した運動状態),
            拘束.引数().接触法線,
        ),
        メートル毎秒::生成する(0.0)
    );
}
