//! 剛体と剛体の接触拘束の履歴と静止摩擦の試験(判断13・判断16)。担当するのは3つの性質を固定することである。
//! 履歴の鍵が2つの剛体の識別子を昇順へ正規化すること、その細分で押し戻していない接触点の静止摩擦が
//! 「法線反力が無い」を返すこと、継続の記録を引き継ぐと錨が置き直され細分の終わりの項目にその錨が載ることである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断16: 接触の履歴は参加者の組ごとに特徴の識別を鍵に全順序の併走で対応付け、暖機はしない」

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ローカル, 変位};

use super::super::body_body_contact_parameters::剛体と剛体の接触拘束の引数;
use super::super::contact_test_fixtures::試験の刻み幅;
use super::super::history::接触の継続の記録;
use super::super::non_penetration::fixture::{剛体どうしの基本の引数, 高さの参加者};
use super::super::non_penetration::非貫通の一回の射影の結果;
use super::super::static_friction::{静止摩擦の一回の射影の結果, 静止摩擦の錨};
use super::剛体と剛体の接触拘束;

fn 局所点(x: f32) -> 変位<ローカル> {
    変位::成分から生成する(メートル::生成する(x), メートル::生成する(0.0), メートル::生成する(0.0))
}

fn 拘束を作る(引数: 剛体と剛体の接触拘束の引数) -> 剛体と剛体の接触拘束 {
    剛体と剛体の接触拘束::引数と刻み幅から生成する(引数, 試験の刻み幅()).unwrap()
}

#[test]
fn 履歴の鍵は二つの剛体の識別子を昇順へ正規化する() {
    let 基本 = 剛体どうしの基本の引数();
    let 逆順 = 剛体と剛体の接触拘束の引数 {
        剛体a: 基本.剛体b,
        剛体b: 基本.剛体a,
        ..基本
    };
    assert_eq!(拘束を作る(基本).履歴の鍵(), 拘束を作る(逆順).履歴の鍵());
    assert!(基本.剛体a != 基本.剛体b, "試験の材料が同じ剛体を指している");
}

#[test]
fn 押し戻していない接触点の静止摩擦は法線反力が無いを返す() {
    let mut 拘束 = 拘束を作る(剛体どうしの基本の引数());
    assert_eq!(
        拘束.静止摩擦を一回射影する(&高さの参加者(0.0), &高さの参加者(-1.0)),
        静止摩擦の一回の射影の結果::法線反力が無い
    );
}

#[test]
fn 押し戻した接触点の静止摩擦は法線反力が無いを返さない() {
    let mut 拘束 = 拘束を作る(剛体どうしの基本の引数());
    let (剛体a, 剛体b) = (高さの参加者(0.0), 高さの参加者(0.1));
    assert!(matches!(拘束.一回射影する(&剛体a, &剛体b), 非貫通の一回の射影の結果::補正した { .. }));
    assert!(拘束.この細分で押し戻したか());
    assert_ne!(拘束.静止摩擦を一回射影する(&剛体a, &剛体b), 静止摩擦の一回の射影の結果::法線反力が無い);
}

#[test]
fn 継続の記録を引き継ぐと細分の終わりの項目にその錨が載る() {
    let mut 拘束 = 拘束を作る(剛体どうしの基本の引数());
    let 引き継ぐ錨 = 静止摩擦の錨::生成する(局所点(0.3), 局所点(-0.4));
    let 記録 = 接触の継続の記録::生成する(引き継ぐ錨, 拘束.引数().接触法線);
    拘束.継続の記録を引き継ぐ(記録);
    assert_eq!(拘束.細分の終わりの履歴の項目().記録().錨(), 引き継ぐ錨);
    assert_eq!(拘束.細分の終わりの履歴の項目().鍵(), 拘束.履歴の鍵());
}
