//! 剛体と剛体の接触拘束の履歴と静止摩擦と速度段階の受け渡しの試験(判断13・判断14・判断16)。担当するのは4つの性質を固定することである。
//! 履歴の鍵が2つの剛体の識別子を昇順へ正規化すること、その細分に法線反力が無い接触点の静止摩擦が
//! 「法線反力が無い」を返すこと、継続の記録を引き継ぐと錨が置き直され細分の終わりの項目にその錨が載ること、
//! 速度段階へ渡す2つの参加点と条件が拘束の引数と解の状態のとおりに組まれることである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断16: 接触の履歴は参加者の組ごとに特徴の識別を鍵に全順序の併走で対応付け、暖機はしない」

