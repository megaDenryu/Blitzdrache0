//! 剛体と剛体の接触点1つの拘束(判断11)。細分の開始で接触点集合から生成し、細分の終了で捨てる一時の値であり、
//! 刻みを跨いで持つ口を持たない(刻みを跨ぐのは判断16の履歴である)。
//! 静的な引数と、細分の刻み幅で導いた係数と、一細分内の状態(非貫通と静止摩擦の2つ)と、錨の4つに分けて持つ
//! (XPBD共通拘束基盤の判断4)。乗数は細分の開始で0から始め、前の細分の値から始める暖機はしない(判断16)。
//! この型を子モジュールへ分けているのは、錨と静止摩擦の解の状態を接触のモジュール全体へ書き換え可能な形で
//! 見せないためである(Rustの可視性はモジュール木で決まる)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

