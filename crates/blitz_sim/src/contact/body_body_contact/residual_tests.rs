//! 剛体どうしの接触点が持ち越す接線の残差の試験(判断24の反証(d)の剛体どうしの側)。担当するのは3つである。
//! 持ち込んだ値と細分の終わりに測った値の差が残差の変化になること、錨を置き直した細分で持ち込みが破棄されること、
//! 粘着の候補が解けなかった細分で持ち込みが破棄されることである。
//! 剛体と静的世界の側(`body_static_contact/residual_tests`)と同じ性質を別に固定するのは、2つの拘束の型が
//! 錨の第2の点の意味も参加点の組み方も違い、片方の配線だけが正しい状態を型が止めないためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 変位, 方向};

use super::super::contact_test_fixtures::試験の刻み幅;
use super::super::history::接触の継続の記録;
use super::super::non_penetration::fixture::{剛体どうしの基本の引数, 高さの参加者};
use super::super::static_friction::{持ち越す接線の残差, 接線のラグランジュ乗数, 静止摩擦の錨};
use super::剛体と剛体の接触拘束;

const 持ち込む長さ: f32 = 1.0e-6;

fn x軸の変位(長さ: f32) -> 変位<ワールド> {
    変位::方向へ進む(方向::生成する(1.0, 0.0, 0.0).unwrap(), メートル::生成する(長さ))
}

// 法線反力を積み、粘着の候補を確定し、前の細分の残差を持ち込んだ拘束。
fn 残差を持ち込んだ拘束() -> 剛体と剛体の接触拘束 {
    let mut 拘束 = 剛体と剛体の接触拘束::引数と刻み幅から生成する(剛体どうしの基本の引数(), 試験の刻み幅()).unwrap();
    let _ = 拘束.一回射影する(&高さの参加者(-0.05), &高さの参加者(0.0));
    拘束.静止摩擦の仮の乗数を確定する(接線のラグランジュ乗数::零());
    let 記録 = 接触の継続の記録::生成する(
        静止摩擦の錨::生成する(拘束.引数().局所接触点a, 拘束.引数().局所接触点b),
        拘束.引数().接触法線,
        持ち越す接線の残差::測った変位から生成する(x軸の変位(持ち込む長さ)),
    );
    拘束.継続の記録を引き継ぐ(記録);
    拘束
}

#[test]
fn 剛体どうしでも持ち込んだ残差と測り直した残差の差が残差の変化になる() {
    let mut 拘束 = 残差を持ち込んだ拘束();
    拘束.細分の終わりの接線の残差を測る(&高さの参加者(-0.05), &高さの参加者(0.0));
    assert!(拘束.接線の残差の持ち越し.細分のあいだの残差の変化().is_some());
}

#[test]
fn 剛体どうしでも錨を置き直した細分は持ち込みを破棄する() {
    let mut 拘束 = 残差を持ち込んだ拘束();
    拘束.接触点集合が滑走中になったと印す(&高さの参加者(-0.05), &高さの参加者(0.0));
    拘束.細分の終わりの接線の残差を測る(&高さの参加者(-0.05), &高さの参加者(0.0));
    assert!(拘束.接線の残差の持ち越し.細分のあいだの残差の変化().is_none());
}

#[test]
fn 剛体どうしでも粘着の候補が解けなかった細分は持ち込みを破棄する() {
    let mut 拘束 = 残差を持ち込んだ拘束();
    拘束.粘着の候補が解けなかったと印す();
    拘束.細分の終わりの接線の残差を測る(&高さの参加者(-0.05), &高さの参加者(0.0));
    assert!(拘束.接線の残差の持ち越し.細分のあいだの残差の変化().is_none());
}
