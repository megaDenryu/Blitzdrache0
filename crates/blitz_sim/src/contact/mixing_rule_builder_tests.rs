//! 混合則の組み立てと係数の値域の試験(判断15)。担当するのは3つの性質を固定することである。値域を破る係数の組が生成で
//! 落ちること(動摩擦が静止摩擦を超える組・反発が1を超える値・負の摩擦)と、同じ鍵の二重登録および登録されていない材質を
//! 指す上書きを組み立てが拒むことと、拒んだ二重登録が先に登録した値を置き換えないことである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断15: 接触物性は両表面の物性から混合則で決め、既定則と材質対の上書き表を持つ」

#![allow(clippy::unwrap_used)]

use super::friction_coefficient::摩擦係数;
use super::material_id::材質の識別子;
use super::mixing_rule_builder::混合則の組み立て;
use super::property_error::接触物性エラー;
use super::property_test_fixtures::{接触物性を作る, 表面物性を作る};
use super::restitution_coefficient::反発係数;
use super::surface_property::表面物性;

#[test]
fn 値域を破る係数の組を生成が拒む() {
    assert_eq!(
        表面物性::生成する(摩擦係数::生成する(0.3).unwrap(), 摩擦係数::生成する(0.5).unwrap(), 反発係数::零()),
        Err(接触物性エラー::動摩擦係数が静止摩擦係数を超えている {
            静止摩擦係数: 0.3,
            動摩擦係数: 0.5,
        })
    );
    assert_eq!(反発係数::生成する(1.5), Err(接触物性エラー::反発係数が値域の外 { 値: 1.5 }));
    assert_eq!(摩擦係数::生成する(-0.1), Err(接触物性エラー::摩擦係数が値域の外 { 値: -0.1 }));
}

#[test]
fn 二重登録と未登録の材質を指す上書きを組み立てが拒む() {
    let mut 組み立て = 混合則の組み立て::生成する();
    let 木 = 材質の識別子::生成する(0);
    組み立て.表面物性を登録する(木, 表面物性を作る(0.6, 0.4, 0.2)).unwrap();
    assert_eq!(
        組み立て.表面物性を登録する(木, 表面物性を作る(0.1, 0.1, 0.1)),
        Err(接触物性エラー::表面物性の二重登録 { 材質の識別子: 0 })
    );
    let 上書き = 接触物性を作る(0.0, 0.0, 0.0);
    組み立て.材質対の上書きを登録する(木, 材質の識別子::生成する(7), 上書き).unwrap();
    assert_eq!(
        組み立て.材質対の上書きを登録する(材質の識別子::生成する(7), 木, 上書き),
        Err(接触物性エラー::材質対の上書きの二重登録 {
            小さい方: 0, 大きい方: 7
        })
    );
    assert_eq!(
        組み立て.組み立てる().err(),
        Some(接触物性エラー::材質の表面物性が未登録 { 材質の識別子: 7 })
    );
}

// 拒否の後に組み立てた混合則が、先に登録した表面物性と上書きをそのまま返すことを見る。挿入してから戻り値で重複を
// 判定する実装では、拒んだはずの2回目の値が表に残り、呼び出し側がエラーを記録して続けたときに実際に使われる。
#[test]
fn 二重登録を拒んだ後も先に登録した値が残る() {
    let mut 組み立て = 混合則の組み立て::生成する();
    let 木 = 材質の識別子::生成する(0);
    let 氷 = 材質の識別子::生成する(1);
    let 先の表面物性 = 表面物性を作る(0.6, 0.4, 0.2);
    let 先の上書き = 接触物性を作る(0.5, 0.3, 0.1);
    組み立て.表面物性を登録する(木, 先の表面物性).unwrap();
    組み立て.表面物性を登録する(氷, 表面物性を作る(0.05, 0.02, 0.1)).unwrap();
    組み立て.材質対の上書きを登録する(木, 氷, 先の上書き).unwrap();
    assert!(組み立て.表面物性を登録する(木, 表面物性を作る(0.1, 0.1, 0.1)).is_err());
    assert!(組み立て.材質対の上書きを登録する(氷, 木, 接触物性を作る(0.0, 0.0, 0.0)).is_err());
    let 混合則 = 組み立て.組み立てる().unwrap();
    assert_eq!(混合則.表面物性を引く(木), Ok(&先の表面物性));
    assert_eq!(混合則.接触物性を求める(木, 氷), Ok(先の上書き));
}
