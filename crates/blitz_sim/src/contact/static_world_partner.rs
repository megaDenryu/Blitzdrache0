//! 静的世界の接触相手: 剛体と静的世界の接触で、剛体でない側を表す名前付きの参加者(判断11)。
//! 識別子・材質の識別子・形の最小の厚みを持ち、配置も速度も質量特性も持たない。位置を持たないのは、接触点の世界位置が
//! 接触点集合から直接返り、細分の間も動かないためである。形そのもの(高さ場の升目・建物の直方体・三角形)は候補の列挙の
//! 工程が持ち、この型は接触拘束を作るのに要る3つだけを持つ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use blitz_collision::shape::形の局所座標の位置;
use blitz_math::{ワールド, 位置};

use super::generation_error::接触拘束の生成エラー;
use super::material_id::材質の識別子;
use super::minimum_thickness::形の最小の厚み;
use super::shared_frame::接触点の位置をワールドへ写す;
use super::static_world_partner_id::静的世界の接触相手の識別子;

/// 剛体と静的世界の接触拘束の第2の参加者。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 静的世界の接触相手 {
    識別子: 静的世界の接触相手の識別子,
    材質: 材質の識別子,
    形の最小の厚み: 形の最小の厚み,
}

impl 静的世界の接触相手 {
    /// コンポジションルートが発行した識別子と、その形が参照する材質と厚みから作る。
    pub fn 生成する(
        識別子: 静的世界の接触相手の識別子, 材質: 材質の識別子, 形の最小の厚み: 形の最小の厚み
    ) -> Self {
        Self {
            識別子,
            材質,
            形の最小の厚み,
        }
    }

    /// 接触の履歴の鍵と反復の順序が読む識別子。
    pub fn 識別子(&self) -> 静的世界の接触相手の識別子 {
        self.識別子
    }

    /// 接触物性を混合則へ問い合わせるための材質の識別子。
    pub fn 材質(&self) -> 材質の識別子 {
        self.材質
    }

    /// 深い初期重なりの切り詰めの上限に使う厚み。
    pub fn 形の最小の厚み(&self) -> 形の最小の厚み {
        self.形の最小の厚み
    }

    /// 接触点集合が返した第2の形の上の点を、細分の間は動かない世界位置として読む。
    pub fn 接触点の世界位置を求める(
        &self,
        共有の座標系の点: 形の局所座標の位置,
    ) -> Result<位置<ワールド>, 接触拘束の生成エラー> {
        接触点の位置をワールドへ写す(共有の座標系の点)
    }
}
