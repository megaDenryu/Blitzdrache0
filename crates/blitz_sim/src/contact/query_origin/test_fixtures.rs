pub(super) const 立方体の半分の長さ: f32 = 0.5;
pub(super) const 帯の粗い横位置: f32 = 16.5; // 粗い位置のx成分。零にすると細かい位置がどんな小ささでも繰り上がるため、20.5と同じ刻みの帯(16以上32未満)で、床(半分の長さ20)の上に置く
pub(super) const 床の半分の長さ: f32 = 20.0;

/// 原点から20メートル離れた座標(y = 20.5)の表現の刻み幅。この座標の帯では1.9073e-6メートルである。
pub(super) fn 二十メートルの帯の刻み() -> f32 {
    メートル::生成する(20.5).表現の刻み幅().値()
}

pub(super) fn 半分の長さ(値: f32) -> 直方体の軸ごとの半分の長さ {
    直方体の軸ごとの半分の長さ::生成する([メートル::生成する(値); 3]).unwrap()
}

/// 粗い位置 (16.5, 粗い高さ, 0) に細かい位置 (細かいx, 細かいy, 0) を足した、恒等の姿勢の配置。細かい位置は刻みの半分未満で与え、繰り上げを起こさない。
pub(super) fn 細かい位置を持つ配置(粗い高さ: f32, 細かいx: f32, 細かいy: f32) -> 配置 {
    粗い横位置も持つ配置(帯の粗い横位置, 粗い高さ, 細かいx, 細かいy)
}

/// 世界の原点に置いた恒等の姿勢の配置。静的な床の中心に使う。
pub(super) fn 世界の原点に置いた配置() -> 配置 {
    粗い横位置も持つ配置(0.0, 0.0, 0.0, 0.0)
}

/// 粗い位置 (粗いx, 粗い高さ, 0) に細かい位置 (細かいx, 細かいy, 0) を足した配置。繰り上げの反証が粗いxを零にして使う。
pub(super) fn 粗い横位置も持つ配置(粗いx: f32, 粗い高さ: f32, 細かいx: f32, 細かいy: f32) -> 配置 {
    let 重心 = 二段の位置::粗い位置と細かい位置から生成する(
        位置::生成する(メートル::生成する(粗いx), メートル::生成する(粗い高さ), メートル::生成する(0.0)),
        変位::成分から生成する(メートル::生成する(細かいx), メートル::生成する(細かいy), メートル::生成する(0.0)),
    )
    .unwrap();
    配置::二段の位置と姿勢から生成する(重心, 姿勢::恒等())
}

/// 2つの直方体の接触点集合を、余白も優位幅も持たない問い合わせで求める。
pub(super) fn 接触点集合を問い合わせる(
    第1: &任意姿勢の直方体,
    第2: &任意姿勢の直方体,
) -> 二つの直方体の重なりの接触点集合 {
    直方体どうしの接触点集合の問い合わせ::二つの直方体と余白と優位幅から生成する(
        第1,
        第2,
        接触生成の余白メートル::余白を持たない(),
        外積の軸へ切り替える優位幅メートル::優位幅を持たない(),
    )
    .二つの直方体の重なりの接触点集合を求める()
    .unwrap()
}

/// 新形: 第1の配置の粗い位置を基準原点に、2つの形をその原点に相対な直方体として問い合わせる。
pub(super) fn 新形で問い合わせる(
    第1: &配置,
    第2: &配置,
    半分: 直方体の軸ごとの半分の長さ,
) -> 二つの直方体の重なりの接触点集合 {
    let 基準原点 = 衝突の問い合わせの基準原点::剛体の粗い位置から選ぶ(第1);
    接触点集合を問い合わせる(
        &基準原点.剛体の相対の直方体を組む(第1, 半分).unwrap(),
        &基準原点.剛体の相対の直方体を組む(第2, 半分).unwrap(),
    )
}

/// 旧形(反証の対照): 2つの位置をそれぞれ最も近い単精度へ畳み、世界座標そのもので組んで問い合わせる。
pub(super) fn 旧形で問い合わせる(
    第1: &配置,
    第2: &配置,
    半分: 直方体の軸ごとの半分の長さ,
) -> 二つの直方体の重なりの接触点集合 {
    接触点集合を問い合わせる(&個別に畳んだ直方体(第1, 半分), &個別に畳んだ直方体(第2, 半分))
}

/// 配置の二段の位置を倍精度で評価した和を最も近い単精度へ丸めた中心で組んだ直方体。旧形の対照だけが使う。
pub(super) fn 個別に畳んだ直方体(配置: &配置, 半分: 直方体の軸ごとの半分の長さ) -> 任意姿勢の直方体 {
    let 和 = 配置.重心の位置().倍精度で評価した位置();
    let 畳んだ = 位置::<ローカル>::生成する(
        メートル::生成する(倍精度の無次元量を単精度へ狭める(和.x().値()).unwrap()),
        メートル::生成する(倍精度の無次元量を単精度へ狭める(和.y().値()).unwrap()),
        メートル::生成する(倍精度の無次元量を単精度へ狭める(和.z().値()).unwrap()),
    );
    let 世界の原点に置いた = 衝突の問い合わせの基準原点::世界の原点().剛体の相対の直方体を組む(
        &配置::生成する(位置::<ワールド>::生成する(畳んだ.x(), 畳んだ.y(), 畳んだ.z()), *配置.姿勢()),
        半分,
    );
    世界の原点に置いた.unwrap()
}

/// 接触点集合の先頭の点の符号付き貫通量。離れていれば無い。
pub(super) fn 先頭の点の貫通量(答え: &二つの直方体の重なりの接触点集合) -> Option<f64> {
    match 答え {
        二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) => {
            集合.接触解法の候補点を順に並べる().next().map(|点| 点.符号付き貫通量().値())
        }
        二つの直方体の重なりの接触点集合::二つの直方体は離れている => None,
    }
}

/// 台帳へ登録した剛体を、与えた基準原点で接触に参加する剛体として読む。厚みは1メートル。
pub(super) fn 参加者を作る(
    台帳: &mut 剛体の台帳, 配置: 配置, 基準原点: 衝突の問い合わせの基準原点
) -> 接触に参加する剛体 {
    接触に参加する剛体::生成する(
        台帳へ登録する(台帳, 配置),
        配置,
        材質の識別子::生成する(試験の材質),
        形の最小の厚み::生成する(メートル::生成する(1.0)).unwrap(),
        基準原点,
    )
}
