//! 衝突の問い合わせの基準原点の反証のうち、細かい位置が繰り上がる場合(判断3の「衝突数学層へ形を渡す境界」)。担当するのは、
//! 粗い位置の成分が零のとき細かい位置がどんな小ささでも粗い位置へ繰り上がり、基準原点がその分だけ動き、静的な床の相対の中心が
//! 同じ分だけ逆向きに動き、剛体自身の相対の中心は零になることを固定することである。基準原点は粗い位置そのものであるため、
//! 繰り上げは基準原点の欠陥ではなく二段の位置の正規化の結果である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断3」の2026-09-09の実装の細目

#![allow(clippy::unwrap_used)]

use super::test_fixtures::{
    世界の原点に置いた配置, 二十メートルの帯の刻み, 半分の長さ, 床の半分の長さ, 立方体の半分の長さ, 粗い横位置も持つ配置
};
use super::衝突の問い合わせの基準原点;

const 箱の粗い高さ: f32 = 20.4999;

#[test]
fn 粗い横位置が零なら細かい横位置は繰り上がり基準原点と床の相対の中心がその分だけ動く() {
    let 細かいx = 二十メートルの帯の刻み() * 0.3;
    let 箱 = 粗い横位置も持つ配置(0.0, 箱の粗い高さ, 細かいx, 0.0);
    let 基準原点 = 衝突の問い合わせの基準原点::剛体の粗い位置から選ぶ(&箱);
    let 動いていない基準原点 =
        衝突の問い合わせの基準原点::剛体の粗い位置から選ぶ(&粗い横位置も持つ配置(0.0, 箱の粗い高さ, 0.0, 0.0));
    assert_ne!(基準原点, 動いていない基準原点, "繰り上げが起きていない");
    let 箱の相対の中心 = 基準原点.剛体の相対の直方体を組む(&箱, 半分の長さ(立方体の半分の長さ)).unwrap().中心();
    assert_eq!(箱の相対の中心.x().値(), 0.0, "繰り上げた後の剛体の相対の中心が零でない");
    let 床 = 衝突の問い合わせの基準原点::世界の原点()
        .剛体の相対の直方体を組む(&世界の原点に置いた配置(), 半分の長さ(床の半分の長さ))
        .unwrap();
    let 床の相対の中心 = 基準原点.静的な直方体を相対の形へ写す(&床).unwrap().中心();
    assert_eq!(床の相対の中心.x().値(), -細かいx, "床の相対の中心が基準原点の動きの逆向きに動いていない");
}
