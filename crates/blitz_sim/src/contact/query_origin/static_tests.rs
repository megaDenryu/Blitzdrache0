//! 衝突の問い合わせの基準原点の反証のうち、静的世界の側(判断3の反証(viii)(ix))。担当するのは、剛体の細かい位置が静的な床へ
//! 向かって+0.4刻みのとき、新形の生成時の符号付き貫通量がそのぶん深くなり旧形では動かないこと、返った静的世界側の点が真の床の面の
//! 上にあること、そして基準原点が同じである限り床の相対の中心が細かい位置に依らず1ビットも動かず、返った点が同じ平面の上に乗ることを
//! 固定することである。畳む旧形はこの反証の対照であり、本番の経路には無い。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断3」の2026-09-09の実装の細目

#![allow(clippy::unwrap_used)]

use blitz_collision::contact_set::二つの直方体の重なりの接触点集合;
use blitz_collision::shape::任意姿勢の直方体;

use super::test_fixtures::{
    世界の原点に置いた配置, 二十メートルの帯の刻み, 個別に畳んだ直方体, 先頭の点の貫通量, 半分の長さ, 床の半分の長さ, 接触点集合を問い合わせる,
    立方体の半分の長さ, 細かい位置を持つ配置,
};
use super::衝突の問い合わせの基準原点;
use crate::rigid_body::配置;

const 食い込み: f32 = 1.0e-4;
const 箱の粗い高さ: f32 = 20.5 - 食い込み; // 床の上面(高さ20.0)へ底面が1e-4メートル食い込む高さ
const 細かい位置の刻みの倍率: f32 = 0.4;

// 世界の原点を中心にした半分の長さ20メートルの静的な床。上面は高さ20.0にある。
fn 静的な床() -> 任意姿勢の直方体 {
    衝突の問い合わせの基準原点::世界の原点()
        .剛体の相対の直方体を組む(&世界の原点に置いた配置(), 半分の長さ(床の半分の長さ))
        .unwrap()
}

fn 新形で床へ問い合わせる(箱: &配置) -> (衝突の問い合わせの基準原点, 二つの直方体の重なりの接触点集合) {
    let 基準原点 = 衝突の問い合わせの基準原点::剛体の粗い位置から選ぶ(箱);
    let 答え = 接触点集合を問い合わせる(
        &基準原点.剛体の相対の直方体を組む(箱, 半分の長さ(立方体の半分の長さ)).unwrap(),
        &基準原点.静的な直方体を相対の形へ写す(&静的な床()).unwrap(),
    );
    (基準原点, 答え)
}

fn 集合を取り出す(
    答え: &二つの直方体の重なりの接触点集合,
) -> &blitz_collision::contact_set::接触点集合<blitz_collision::contact_set::直方体どうしの接触の特徴の対> {
    let 二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) = 答え else {
        panic!("箱が床へ食い込んでいるのに接触点集合が返らない");
    };
    集合
}

/// 反証(viii): 細かい位置が床へ向かって+0.4刻みのとき、新形の貫通量は0.4刻みだけ深くなり、旧形では動かない。
/// 返った静的世界側の点は、基準原点から戻すと真の床の上面(高さ20.0)の上にある。
#[test]
fn 床へ向かう細かい位置が貫通量を深くし静的世界側の点は真の床の面の上にある() {
    let 刻み = 二十メートルの帯の刻み();
    let 細かい = 刻み * 細かい位置の刻みの倍率;
    let (細かい位置なし, 細かい位置あり) = (
        細かい位置を持つ配置(箱の粗い高さ, 0.0, 0.0),
        細かい位置を持つ配置(箱の粗い高さ, 0.0, -細かい),
    );
    let 新形の差 =
        先頭の点の貫通量(&新形で床へ問い合わせる(&細かい位置あり).1).unwrap() - 先頭の点の貫通量(&新形で床へ問い合わせる(&細かい位置なし).1).unwrap();
    assert!(
        (新形の差 - f64::from(細かい)).abs() < f64::from(刻み) * 0.05,
        "新形の貫通量の差={新形の差:e}"
    );
    let 半分 = 半分の長さ(立方体の半分の長さ);
    let 旧形の差 = 先頭の点の貫通量(&接触点集合を問い合わせる(
        &個別に畳んだ直方体(&細かい位置あり, 半分),
        &静的な床(),
    ))
    .unwrap()
        - 先頭の点の貫通量(&接触点集合を問い合わせる(
            &個別に畳んだ直方体(&細かい位置なし, 半分),
            &静的な床(),
        ))
        .unwrap();
    assert_eq!(旧形の差, 0.0, "個別に畳む旧形で貫通量が動いた");
    let (基準原点, 答え) = 新形で床へ問い合わせる(&細かい位置あり);
    for 点 in 集合を取り出す(&答え).接触解法の候補点を順に並べる() {
        let 世界 = 基準原点
            .衝突が返した点を世界の二段の位置へ戻す(点.第2の形の上の位置())
            .unwrap()
            .倍精度で評価した位置();
        assert!(
            (世界.y().値() - f64::from(床の半分の長さ)).abs() < 1.0e-7,
            "静的世界側の点の高さ={:e}",
            世界.y().値()
        );
    }
}

/// 反証(ix): 基準原点(箱の粗い位置)が同じである限り、床の相対の中心は箱の細かい位置に依らず1ビットも動かず、返った静的世界側の
/// 点は床の上面と同じ平面(相対の高さが床の相対の中心の高さ + 半分の長さ)の上に乗る。一定の偏りは錨からの接線変位を動かさない。
/// 細かい位置は刻みの半分未満で与え、繰り上げを起こさない(繰り上げが起きる場合の期待は `carry_tests`)。
#[test]
fn 基準原点が同じなら床の相対の形は細かい位置に依らず動かず点は同じ平面に乗る() {
    let 刻み = 二十メートルの帯の刻み();
    let 基準 = 新形で床へ問い合わせる(&細かい位置を持つ配置(箱の粗い高さ, 0.0, 0.0));
    let 基準の床 = 基準.0.静的な直方体を相対の形へ写す(&静的な床()).unwrap();
    let 床の上面の相対の高さ = f64::from(基準の床.中心().y().値()) + f64::from(床の半分の長さ);
    for (細かいx, 細かいy) in [(0.0, 0.2), (0.0, -0.4), (0.3, 0.0), (-0.3, 0.1)] {
        let (基準原点, 答え) = 新形で床へ問い合わせる(&細かい位置を持つ配置(箱の粗い高さ, 刻み * 細かいx, 刻み * 細かいy));
        assert_eq!(基準原点, 基準.0);
        assert_eq!(
            基準原点.静的な直方体を相対の形へ写す(&静的な床()).unwrap(),
            基準の床,
            "床の相対の形が細かい位置で動いた"
        );
        for 点 in 集合を取り出す(&答え).接触解法の候補点を順に並べる() {
            let 高さ = 点.第2の形の上の位置().yのメートル();
            assert!(
                (高さ - 床の上面の相対の高さ).abs() < 1.0e-12,
                "静的世界側の点が床の平面から外れた: {高さ:e}"
            );
        }
    }
}
