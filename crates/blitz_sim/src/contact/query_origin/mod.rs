//! 衝突の問い合わせの基準原点: 1回の接触点集合の問い合わせで2つの形が共有する局所座標系の原点として選ぶ、
//! 単精度で正確に表せる世界位置(判断3の「衝突数学層へ形を渡す境界」)。
//! 衝突数学層の `任意姿勢の直方体` は中心を単精度で持つ。2つの剛体の位置を個別に単精度へ畳んでから渡すと、2つの細かい位置の
//! 差(1e-6メートルの桁)が丸めで消える。この型は第1の参加者の粗い位置を原点に選び、各形の位置をこの原点からの相対変位
//! (`二段の位置 − 位置`)として単精度へ落とす。第1の参加者の相対の中心は (a粗 − a粗) + a細 = a細 そのものであり丸めが無い。
//! 第2の参加者の相対の中心 (b粗 − a粗) + b細 のうち b粗 − a粗 は、2つの成分が同符号で2倍以内にあるとき(Sterbenzの補題)
//! 単精度で厳密であり、接触しうる対はこの範囲にある。成分が符号をまたぐ原点付近ではこの差に丸めが入るが、その丸めは
//! 相対距離の刻み(1メートルで6e-8メートル)であり、細かい位置の差より1桁以上小さい。
//! 返った点はこの原点からの相対座標である。世界へ戻すときは、原点を粗い位置・相対の変位を細かい位置にした二段の位置へ繰り上げる。
//! 注意: 形の中心が単精度である限り、原点から形の中心までの距離の表現の刻み幅の半分が、その形の配置の丸めの上限になる。
//! 剛体の側は零であり、半分の長さ20メートルの静的な直方体では9.5e-7メートルの偏りが基準原点が変わるまで一定に残る。
//! このモジュールは、共有する座標系の境界を成す3つを持つ。原点(この型)・原点に相対な直方体を大域へ写す `relative_box`・
//! 相対座標の点と法線と貫通量を単精度へ狭める `shared_frame` である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断3」「判断11」

