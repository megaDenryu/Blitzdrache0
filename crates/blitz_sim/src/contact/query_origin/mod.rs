/// 1回の接触点集合の問い合わせで2つの形が共有する局所座標系の原点。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 衝突の問い合わせの基準原点 {
    位置: 位置<ワールド>,
}

impl 衝突の問い合わせの基準原点 {
    /// 第1の参加者の剛体の粗い位置を原点に選ぶ。その剛体の相対の中心は細かい位置そのものになる。
    pub fn 剛体の粗い位置から選ぶ(配置: &配置) -> Self {
        Self {
            位置: 配置.重心の位置().基準原点を選ぶための粗い位置(),
        }
    }

    /// 世界の原点。形を世界座標そのもので組む試験の材料が使う。
    pub fn 世界の原点() -> Self {
        Self {
            位置: 位置::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0)),
        }
    }

    /// 剛体の重心のこの原点からの相対の中心。二段の位置との差を2段の意味を保って求め、形の局所座標の位置として読む。
    pub fn 剛体の相対の中心を求める(&self, 配置: &配置) -> 位置<ローカル> {
        let 相対 = 配置.重心の位置() - self.位置;
        位置::生成する(相対.x(), 相対.y(), 相対.z())
    }

    /// 剛体の形をこの原点に相対な直方体として組む。返った直方体の中心が、返った点を写すときに引く相対の中心である。
    pub fn 剛体の相対の直方体を組む(
        &self,
        配置: &配置,
        半分の長さ: 直方体の軸ごとの半分の長さ,
    ) -> Result<任意姿勢の直方体, 接触拘束の生成エラー> {
        let [x, y, z, w] = 配置.姿勢().境界用xyzw配列();
        Ok(任意姿勢の直方体::生成する(
            self.剛体の相対の中心を求める(配置),
            クォータニオン::<ローカル, ローカル>::生成する(x, y, z, w)?,
            半分の長さ,
        )?)
    }

    /// 世界座標で持つ静的な直方体を、この原点に相対な直方体へ写す。中心の差は2つの単精度の差であり、原点から中心までの
    /// 距離の刻みの半分の丸めが入る(型の冒頭の注意)。
    pub fn 静的な直方体を相対の形へ写す(
        &self,
        直方体: &任意姿勢の直方体,
    ) -> Result<任意姿勢の直方体, 接触拘束の生成エラー> {
        let 中心 = 直方体.中心();
        Ok(任意姿勢の直方体::生成する(
            位置::生成する(中心.x() - self.位置.x(), 中心.y() - self.位置.y(), 中心.z() - self.位置.z()),
            直方体.回転(),
            直方体.軸ごとの半分の長さ(),
        )?)
    }

    /// 衝突数学層が返したこの原点からの相対の点を、原点を粗い位置・相対の変位を細かい位置にした二段の位置へ戻す。
    pub fn 衝突が返した点を世界の二段の位置へ戻す(
        &self,
        点: 形の局所座標の位置,
    ) -> Result<二段の位置<ワールド>, 接触拘束の生成エラー> {
        Ok(二段の位置::粗い位置と細かい位置から生成する(
            self.位置,
            接触点を基準原点からの変位へ写す(点)?,
        )?)
    }

    /// この原点に相対な位置を世界の単精度の位置として読む。接触生成の余白の導出が座標の刻みの根拠にする長さを数えるためだけに使い、
    /// 解法の幾何へは渡さない(細かい位置の桁は要らない)。
    pub fn 相対の位置を世界の位置として読む(&self, 相対の位置: 位置<ローカル>) -> 位置<ワールド> {
        位置::生成する(
            self.位置.x() + 相対の位置.x(),
            self.位置.y() + 相対の位置.y(),
            self.位置.z() + 相対の位置.z(),
        )
    }

    /// 粗い選別の箱をこの原点から大域へ写すときの大域原点。
    pub fn 大域の原点として読む(&self) -> 大域ワールド位置 {
        大域ワールド位置::局所ワールド位置から生成する(self.位置)
    }
}
