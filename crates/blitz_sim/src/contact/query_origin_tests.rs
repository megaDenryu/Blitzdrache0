//! 衝突の問い合わせの基準原点の反証のうち、剛体対の側(判断3の反証(vi)(vii))。担当するのは、同じ粗い位置の高さで面を接する
//! 2つの箱の細かい位置の差(+0.3刻みと−0.3刻み)が、新形では接触の事実と貫通量に現れ、2つの位置を個別に畳む旧形では消えることを
//! 固定することである。畳む旧形はこの反証の対照であり、本番の経路には無い。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断3」の2026-09-09の実装の細目

#![allow(clippy::unwrap_used)]

use blitz_collision::contact_set::二つの直方体の重なりの接触点集合;

use super::query_origin_test_fixtures::{
    二十メートルの帯の刻み, 先頭の点の貫通量, 半分の長さ, 新形で問い合わせる, 旧形で問い合わせる, 立方体の半分の長さ, 細かい位置を持つ配置,
};

const 上の箱の粗い高さ: f32 = 20.5;
const 下の箱の粗い高さ: f32 = 19.5; // 上の箱の底面と下の箱の上面が高さ20.0で厳密に接する
const 細かい位置の刻みの倍率: f32 = 0.3;
const 食い込み: f32 = 1.0e-4;

fn 離れているか(答え: &二つの直方体の重なりの接触点集合) -> bool {
    matches!(答え, 二つの直方体の重なりの接触点集合::二つの直方体は離れている)
}

/// 反証(vi): 厳密に接する2つの箱の細かい位置を互いに離す向きへ0.3刻みずつ与えると新形は離れていると答え、近づける向きなら
/// 重なっていると答える。旧形は畳みで細かい位置を落とすため、どちらの向きでも同じ答えになる。
#[test]
fn 逆向きの細かい位置が接触の事実を分けるが個別に畳むと分けない() {
    let 細かい = 二十メートルの帯の刻み() * 細かい位置の刻みの倍率;
    let 離す組 = (
        細かい位置を持つ配置(上の箱の粗い高さ, 0.0, 細かい),
        細かい位置を持つ配置(下の箱の粗い高さ, 0.0, -細かい),
    );
    let 近づける組 = (
        細かい位置を持つ配置(上の箱の粗い高さ, 0.0, -細かい),
        細かい位置を持つ配置(下の箱の粗い高さ, 0.0, 細かい),
    );
    let 半分 = 半分の長さ(立方体の半分の長さ);
    assert!(
        離れているか(&新形で問い合わせる(&離す組.0, &離す組.1, 半分)),
        "離す向きの細かい位置で接触点集合が返った"
    );
    assert!(
        !離れているか(&新形で問い合わせる(&近づける組.0, &近づける組.1, 半分)),
        "近づける向きの細かい位置で接触点集合が返らない"
    );
    assert_eq!(
        離れているか(&旧形で問い合わせる(&離す組.0, &離す組.1, 半分)),
        離れているか(&旧形で問い合わせる(&近づける組.0, &近づける組.1, 半分)),
        "個別に畳む旧形が細かい位置の向きで答えを変えた"
    );
}

/// 反証(vii): 食い込み1e-4メートルの上下の箱で、細かい位置を上に−0.3刻み・下に+0.3刻み与えると、新形の生成時の符号付き貫通量は
/// 0.6刻みだけ深くなる。旧形では1ビットも動かない。
#[test]
fn 逆向きの細かい位置が貫通量を六割刻み深くするが個別に畳むと動かない() {
    let 刻み = 二十メートルの帯の刻み();
    let 細かい = 刻み * 細かい位置の刻みの倍率;
    let 半分 = 半分の長さ(立方体の半分の長さ);
    let 上の粗い高さ = 上の箱の粗い高さ - 食い込み;
    let 細かい位置なし = (
        細かい位置を持つ配置(上の粗い高さ, 0.0, 0.0),
        細かい位置を持つ配置(下の箱の粗い高さ, 0.0, 0.0),
    );
    let 細かい位置あり = (
        細かい位置を持つ配置(上の粗い高さ, 0.0, -細かい),
        細かい位置を持つ配置(下の箱の粗い高さ, 0.0, 細かい),
    );
    let 新形の差 = 先頭の点の貫通量(&新形で問い合わせる(&細かい位置あり.0, &細かい位置あり.1, 半分)).unwrap()
        - 先頭の点の貫通量(&新形で問い合わせる(&細かい位置なし.0, &細かい位置なし.1, 半分)).unwrap();
    let 期待の差 = f64::from(細かい) * 2.0;
    assert!(
        (新形の差 - 期待の差).abs() < f64::from(刻み) * 0.05,
        "新形の貫通量の差={新形の差:e} 期待={期待の差:e}"
    );
    let 旧形の差 = 先頭の点の貫通量(&旧形で問い合わせる(&細かい位置あり.0, &細かい位置あり.1, 半分)).unwrap()
        - 先頭の点の貫通量(&旧形で問い合わせる(&細かい位置なし.0, &細かい位置なし.1, 半分)).unwrap();
    assert_eq!(旧形の差, 0.0, "個別に畳む旧形で貫通量が動いた");
}
