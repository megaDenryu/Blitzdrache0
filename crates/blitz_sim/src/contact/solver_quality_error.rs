//! 接触を解く品質の設定が拒んだ値(判断19)。回数が0はその段を解かないことを意味するため、生成が拒む。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断19: 剛体は基本刻みを整数nで細分し、細分1本の中で予測・接触・反復・速度再構成・速度段階を回す」

use thiserror::Error;

/// 接触を解く品質の設定の生成が拒んだ値。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 接触を解く品質の設定エラー {
    /// 位置の反復回数が0である。1回も解かない設定は拘束を外すことと同じであり、品質の設定では表せない。
    #[error("位置の反復回数は1以上でなければならない")]
    位置の反復回数が零,
    /// 速度段階の巡回数が0である。反発も動摩擦も適用しない設定は品質の設定では表せない。
    #[error("速度段階の巡回数は1以上でなければならない")]
    速度段階の巡回数が零,
}
