//! 表面物性: 1つの表面が持つ静止摩擦係数・動摩擦係数・反発係数の組(判断15)。衝突形状の子形状が材質の識別子で参照し、
//! 混合則が材質の識別子から引く。接触1つの物性は、2つの表面物性を既定則か材質対の上書きで混ぜて決める。
//! 既定則は摩擦が相乗平均、反発が最大値であり、どちらも引数の順で結果が変わらない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断15: 接触物性は両表面の物性から混合則で決め、既定則と材質対の上書き表を持つ」

use super::contact_property::接触物性;
use super::friction_coefficient::摩擦係数;
use super::property_error::接触物性エラー;
use super::restitution_coefficient::反発係数;

/// 1つの表面が持つ摩擦と反発の3つの係数。生成が 0 ≤ μ_d ≤ μ_s と 0 ≤ e ≤ 1 を検査する。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 表面物性 {
    静止摩擦係数: 摩擦係数,
    動摩擦係数: 摩擦係数,
    反発係数: 反発係数,
}

impl 表面物性 {
    /// 動摩擦係数が静止摩擦係数を超える組を型付きエラーで拒む。各係数の値域は係数の型が生成で守る。
    pub fn 生成する(
        静止摩擦係数: 摩擦係数, 動摩擦係数: 摩擦係数, 反発係数: 反発係数
    ) -> Result<Self, 接触物性エラー> {
        if 動摩擦係数 > 静止摩擦係数 {
            return Err(接触物性エラー::動摩擦係数が静止摩擦係数を超えている {
                静止摩擦係数: 静止摩擦係数.値(),
                動摩擦係数: 動摩擦係数.値(),
            });
        }
        Ok(Self::検査済みの係数から組む(静止摩擦係数, 動摩擦係数, 反発係数))
    }

    // 既定則の混合が作る係数の入口。相乗平均は 0 ≤ μ_d ≤ μ_s を保ち、最大値は反発の値域を保つため、検査を通し直さない。
    pub(super) fn 検査済みの係数から組む(
        静止摩擦係数: 摩擦係数, 動摩擦係数: 摩擦係数, 反発係数: 反発係数
    ) -> Self {
        Self {
            静止摩擦係数,
            動摩擦係数,
            反発係数,
        }
    }

    /// 滑り出す限界を決める摩擦係数。
    pub fn 静止摩擦係数(&self) -> 摩擦係数 {
        self.静止摩擦係数
    }

    /// 滑走中の抵抗を決める摩擦係数。
    pub fn 動摩擦係数(&self) -> 摩擦係数 {
        self.動摩擦係数
    }

    /// 跳ね返りの強さを決める反発係数。
    pub fn 反発係数(&self) -> 反発係数 {
        self.反発係数
    }

    /// 既定則(摩擦は相乗平均・反発は最大値)で相手の表面物性と混ぜた接触物性。相乗平均も最大値も可換である。
    pub fn 既定則で接触物性を求める(&self, 相手: &Self) -> 接触物性 {
        接触物性::検査済みの係数から組む(
            self.静止摩擦係数.相乗平均を求める(相手.静止摩擦係数),
            self.動摩擦係数.相乗平均を求める(相手.動摩擦係数),
            self.反発係数.大きい方を求める(相手.反発係数),
        )
    }
}
