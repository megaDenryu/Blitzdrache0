pub(super) const 試験の材質: u32 = 0;

pub(super) fn 世界の位置を作る(x: f32, y: f32, z: f32) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

pub(super) fn 形の位置を作る(x: f32, y: f32, z: f32) -> 位置<ローカル> {
    位置::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

pub(super) fn 局所の変位を作る(x: f32, y: f32, z: f32) -> 変位<ローカル> {
    変位::成分から生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

pub(super) fn 直方体を作る(中心: 位置<ローカル>, 姿勢: 姿勢, 半分の長さ: f32) -> 任意姿勢の直方体 {
    let 半分 = 直方体の軸ごとの半分の長さ::生成する([メートル::生成する(半分の長さ); 3]).unwrap();
    let [x, y, z, w] = 姿勢.境界用xyzw配列();
    任意姿勢の直方体::生成する(中心, クォータニオン::生成する(x, y, z, w).unwrap(), 半分).unwrap()
}

pub(super) fn 直方体どうしの接触点集合を求める(
    第1: &任意姿勢の直方体,
    第2: &任意姿勢の直方体,
) -> 接触点集合<直方体どうしの接触の特徴の対> {
    let 問い合わせ =
        直方体どうしの接触点集合の問い合わせ::二つの直方体と余白から生成する(第1, 第2, 接触生成の余白().unwrap());
    match 問い合わせ.二つの直方体の重なりの接触点集合を求める().unwrap() {
        二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) => 集合,
        二つの直方体の重なりの接触点集合::二つの直方体は離れている => {
            panic!("試験の材料の2つの直方体が重なっていない")
        }
    }
}

pub(super) fn 単一の材質の混合則() -> 混合則 {
    let mut 組み立て = 混合則の組み立て::生成する();
    let 物性 = 表面物性::生成する(
        摩擦係数::生成する(0.5).unwrap(),
        摩擦係数::生成する(0.4).unwrap(),
        反発係数::生成する(0.2).unwrap(),
    )
    .unwrap();
    組み立て.表面物性を登録する(材質の識別子::生成する(試験の材質), 物性).unwrap();
    組み立て.組み立てる().unwrap()
}

pub(super) fn 質量特性を作る(質量: f32, 主慣性の値: f32) -> 質量特性 {
    let 成分 = キログラム平方メートル::生成する(主慣性の値);
    let 主慣性と主軸 = 主慣性と主軸::生成する(主慣性::生成する(成分, 成分, 成分), クォータニオン::軸が一致する回転()).unwrap();
    質量特性::生成する(キログラム::生成する(質量).unwrap(), 変位::零(), 主慣性と主軸).unwrap()
}

pub(super) fn 台帳へ登録する(台帳: &mut 剛体の台帳, 配置: 配置) -> 剛体の識別子 {
    台帳
        .登録する(配置, 質量特性を作る(1.0, 1.0), 運動種別::動的で始める(運動状態::静止()))
        .unwrap()
}

pub(super) fn 接触に参加する剛体を作る(識別子: 剛体の識別子, 配置: 配置) -> 接触に参加する剛体 {
    接触に参加する剛体::生成する(
        識別子,
        配置,
        材質の識別子::生成する(試験の材質),
        形の最小の厚み::生成する(メートル::生成する(1.0)).unwrap(),
    )
}

pub(super) fn 静的世界の接触相手を作る(番号: u32) -> 静的世界の接触相手 {
    静的世界の接触相手::生成する(
        静的世界の接触相手の識別子::生成する(番号),
        材質の識別子::生成する(試験の材質),
        形の最小の厚み::生成する(メートル::生成する(1.0)).unwrap(),
    )
}

pub(super) fn 動的な参加者を作る(配置: 配置, 質量: f32, 主慣性の値: f32) -> 姿勢自由度の参加者 {
    姿勢自由度の参加者::動的(配置, &質量特性を作る(質量, 主慣性の値))
}

pub(super) fn 試験の刻み幅() -> 刻み幅 {
    刻み幅::生成する(秒::生成する(1.0 / 480.0)).unwrap()
}
