//! 接触拘束の生成と非貫通の試験が共有する材料。担当するのは、直方体2つから実際の接触点集合を作ることと、
//! 単一の材質だけを登録した混合則と、既知の配置を持つ参加者を組むことである。
//! 接触点集合を手で組み立てず衝突数学層の問い合わせから作るのは、生成の工程が受け取る値の並びと不変条件
//! (第2の形の上の点は第1の形の上の点から法線の向きへ符号付き貫通量だけ戻った点である)を試験でも本物に保つためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

