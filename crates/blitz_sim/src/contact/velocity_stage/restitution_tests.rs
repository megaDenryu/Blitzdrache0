//! 速度段階の反発の試験(判断14)。担当するのは2つの性質を固定することである。反発の後の法線相対速度が
//! ニュートンの反発則 −e v_n⁻ になること、低速の抑制(|v_n⁻| ≤ v_閾値)が働くと反発が零に落ちることである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

#![allow(clippy::unwrap_used)]

use super::impulse_fixture::{
    下向きの接触法線, 反発係数の値, 抑制の閾値, 適用する, 重心が接触点の剛体, 静的世界の接触点
};
use super::result::接触の速度段階の結果;
use super::stage::接触点の法線の相対速度を求める;

#[test]
fn 反発の後の法線相対速度はニュートンの反発則の値になる() {
    // 剛体が下向きに落ちてくる場面。法線は剛体から静的世界へ向かうため、接近は法線相対速度の負である。
    let 衝突前の法線相対速度 = -4.0;
    let 結果 = 適用する(0.0, -4.0, 0.0, 1.0, 衝突前の法線相対速度, false);
    let 接触の速度段階の結果::衝撃を適用した {
        適用後のaの運動状態,
    ..
    } = 結果
    else {
        panic!("衝撃を適用した枝が返っていない");
    };
    let 適用後 =
        接触点の法線の相対速度を求める(重心が接触点の剛体(適用後のaの運動状態.並進速度()), 静的世界の接触点(), 下向きの接触法線());
    assert!((適用後.値() - -反発係数の値 * 衝突前の法線相対速度).abs() < 1.0e-5);
}

#[test]
fn 低速の抑制が働くと反発が零に落ちる() {
    let 結果 = 適用する(0.0, -0.5 * 抑制の閾値, 0.0, 1.0, -0.5 * 抑制の閾値, false);
    let 接触の速度段階の結果::衝撃を適用した {
        適用後のaの運動状態,
    ..
    } = 結果
    else {
        panic!("衝撃を適用した枝が返っていない");
    };
    let 適用後 =
        接触点の法線の相対速度を求める(重心が接触点の剛体(適用後のaの運動状態.並進速度()), 静的世界の接触点(), 下向きの接触法線());
    assert!(適用後.値().abs() < 1.0e-6, "低速でも跳ね返っている: {適用後:?}");
}
