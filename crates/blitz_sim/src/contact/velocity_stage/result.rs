//! 接触点1つへ速度段階を適用した結果(判断14)。適用後の2つの運動状態と、実際に与えた2つの衝撃の大きさを持つ。
//! 参加点そのものでなく運動状態を返すのは、呼び出し側が台帳へ書き戻すのが運動状態だけであり、
//! 配置を含む参加点を返すと「速度段階は位置と姿勢を書き換えない」という契約が戻り値の側から曖昧になるためである。
//! 衝撃の大きさを返すのは、動摩擦の上限が効いたかどうかと反発の強さを検査と計器が読むためである。
//! 「法線反力が無い」は、その細分の法線のラグランジュ乗数が0の接触点である。動摩擦の上限(μ_d λ_n ÷ h)が
//! 実在しない法線反力から作られることを防ぐ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

use blitz_math::ニュートン秒;

use crate::rigid_body::運動状態;

/// 接触1点の速度段階の結果。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 接触の速度段階の結果 {
    /// 動摩擦と反発を順に適用した。呼び出し側は2つの運動状態を台帳へ書き戻す。
    衝撃を適用した {
        適用後のaの運動状態: 運動状態,
        適用後のbの運動状態: 運動状態,
        動摩擦の衝撃: ニュートン秒,
        反発の衝撃: ニュートン秒,
    },
    /// その細分の法線のラグランジュ乗数が0であり、法線反力が存在しない。
    法線反力が無い,
    /// 両方の参加者が静的か運動学的で、どちらも動かせない。
    両方が動かせない,
}
