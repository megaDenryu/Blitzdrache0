//! 接触の速度段階(判断14)。細分の速度の再構成の後に、接触点ごとの相対速度から動摩擦と反発を衝撃として1箇所ずつ適用する。
//! この型は刻み幅と低速の抑制の閾値だけを保持し、配置と姿勢を書き換える口を持たない(書き換えられるのは運動状態だけである)。
//!   動摩擦: t̂ = v_t ÷ |v_t|、j_t = min(μ_d λ_n ÷ h, |v_t| ÷ w̃_t)、P = −j_t t̂
//!   反発:   j_n = (−v_n + max(−e v_n⁻, 0)) ÷ w̃_n、P = j_n n
//! 動摩擦を先に適用してから相対速度を測り直すのは、接線の衝撃が角速度を変えると法線方向の相対速度も変わるためである。
//! 反発の式は j_n の符号で場合を分けない。負の j_n は、位置の補正が押し戻して作った過剰な分離の速さを反発則の値まで
//! 落とす向きであり、静置した箱が押し戻しの速度で毎細分わずかに浮くことをこれが断つ。判断14が禁じる
//! 「既に離れていく接触(v_n > 0 で d ≥ 0)への再注入」は、隔たりが0以上の接触点をこの段が受け取らないことで満たす
//! (呼び出し側が判断12の契約に従い、その細分で押し戻した接触点だけを渡す)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

use blitz_math::{ニュートン秒, メートル毎秒, ワールド, 方向, 衝撃, 速度};

use super::condition::速度段階の接触点の条件;
use super::participant::速度段階の参加点;
use super::result::接触の速度段階の結果;
use crate::xpbd::刻み幅;

// 衝撃を1つ適用した後の両側と、その衝撃の大きさ。2つの工程を順に通すための私有の受け渡しである。
pub(super) struct 衝撃を適用した後の両側 {
    pub(super) a: 速度段階の参加点,
    pub(super) b: 速度段階の参加点,
    pub(super) 衝撃の大きさ: ニュートン秒,
}

/// 細分1本の速度段階。刻み幅と低速の反発の抑制の閾値を保持する。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触の速度段階 {
    pub(super) 刻み幅: 刻み幅,
    反発を抑制する法線相対速度の閾値: メートル毎秒,
}

impl 接触の速度段階 {
    /// 細分1本の刻み幅と、低速の反発の抑制の閾値 v_閾値 から作る。閾値は `contact_thresholds` が刻み幅と重力から導く。
    pub fn 生成する(刻み幅: 刻み幅, 反発を抑制する法線相対速度の閾値: メートル毎秒) -> Self {
        Self {
            刻み幅,
            反発を抑制する法線相対速度の閾値,
        }
    }

    /// 接触点1つへ動摩擦と反発を順に適用する。第1の参加者へは衝撃の逆、第2の参加者へは衝撃そのものを与える。
    pub fn 一点へ適用する(
        &self, a: 速度段階の参加点, b: 速度段階の参加点, 条件: 速度段階の接触点の条件
    ) -> 接触の速度段階の結果 {
        if a.動かせないか() && b.動かせないか() {
            return 接触の速度段階の結果::両方が動かせない;
        }
        let 動摩擦の後 = self.動摩擦の衝撃を適用する(a, b, &条件);
        let 反発の後 = self.反発の衝撃を適用する(動摩擦の後.a, 動摩擦の後.b, &条件);
        接触の速度段階の結果::衝撃を適用した {
            適用後のaの運動状態: 反発の後.a.運動状態(),
            適用後のbの運動状態: 反発の後.b.運動状態(),
            動摩擦の衝撃: 動摩擦の後.衝撃の大きさ,
            反発の衝撃: 反発の後.衝撃の大きさ,
        }
    }

    /// 反発だけを1巡ぶん適用する。動摩擦の衝撃は1細分に1度だけ与える量であるため、この口では触れない。
    /// 接触点が2つ以上ある面と面の接触では、点を順に1巡しただけでは各点の法線相対速度が同時には目標へ揃わず、
    /// 剛体に偽の回転が残る(平らな箱を1メートル落とす場面で角速度1.36ラジアン毎秒、跳ね返りの高さで5パーセントの
    /// 取りこぼし)。呼び出し側は動摩擦を含む1巡の後、この口で数巡を回して法線の条件を揃える。
    pub fn 一点へ反発だけ適用する(
        &self,
        a: 速度段階の参加点,
        b: 速度段階の参加点,
        条件: 速度段階の接触点の条件,
    ) -> 接触の速度段階の結果 {
        if a.動かせないか() && b.動かせないか() {
            return 接触の速度段階の結果::両方が動かせない;
        }
        let 反発の後 = self.反発の衝撃を適用する(a, b, &条件);
        接触の速度段階の結果::衝撃を適用した {
            適用後のaの運動状態: 反発の後.a.運動状態(),
            適用後のbの運動状態: 反発の後.b.運動状態(),
            動摩擦の衝撃: ニュートン秒::生成する(0.0),
            反発の衝撃: 反発の後.衝撃の大きさ,
        }
    }

    // 法線方向の相対速度をニュートンの反発則が求める分離の速さへ引き上げる衝撃を与える。
    fn 反発の衝撃を適用する(
        &self,
        a: 速度段階の参加点,
        b: 速度段階の参加点,
        条件: &速度段階の接触点の条件,
    ) -> 衝撃を適用した後の両側 {
        let 接触法線 = 条件.接触法線();
        let 法線の相対速度 = 相対速度を求める(a, b).方向に沿う成分(接触法線);
        let 目標の分離の速さ = if 条件.予測の前の法線相対速度().大きさ() <= self.反発を抑制する法線相対速度の閾値 {
            メートル毎秒::生成する(0.0)
        } else {
            条件.接触物性().反発係数().跳ね返り後の分離の速さを求める(条件.予測の前の法線相対速度())
        };
        let 大きさ = (目標の分離の速さ - 法線の相対速度) / (a.一般化逆質量(接触法線) + b.一般化逆質量(接触法線));
        両側へ与える(a, b, 衝撃::方向へ生成する(接触法線, 大きさ), 大きさ)
    }
}

/// 2つの接触点の相対速度の法線成分 v_n。細分の予測の直後に測った値が判断14の v_n⁻ である。
/// 2つの参加点は対等な入力であるため、レシーバを持たない自由関数である。
pub fn 接触点の法線の相対速度を求める(
    a: 速度段階の参加点, b: 速度段階の参加点, 接触法線: 方向<ワールド>
) -> メートル毎秒 {
    相対速度を求める(a, b).方向に沿う成分(接触法線)
}

// 接触点の相対速度 (v_B + ω_B × r_B) − (v_A + ω_A × r_A)。2つの参加点は対等である。
pub(super) fn 相対速度を求める(a: 速度段階の参加点, b: 速度段階の参加点) -> 速度<ワールド> {
    b.接触点の速度() - a.接触点の速度()
}

// 第2の参加者へ衝撃そのものを、第1の参加者へその逆を与える。2つの参加点は対等である。
pub(super) fn 両側へ与える(
    a: 速度段階の参加点,
    b: 速度段階の参加点,
    与える衝撃: 衝撃<ワールド>,
    衝撃の大きさ: ニュートン秒,
) -> 衝撃を適用した後の両側 {
    衝撃を適用した後の両側 {
        a: a.衝撃を受けた参加点(-与える衝撃),
        b: b.衝撃を受けた参加点(与える衝撃),
        衝撃の大きさ,
    }
}
