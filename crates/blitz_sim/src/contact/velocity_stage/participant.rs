//! 速度段階に参加する接触点の片側(判断14)。接触の射影に参加する点と、その参加者の運動状態の組である。
//! 衝撃を受けた後の値を新しい参加点として返し、自分を書き換えない。位置と姿勢を持たないのではなく、
//! 書き換える口を持たないのがこの型の要点であり、速度段階が配置を動かせないことをここで型に閉じる。
//! 静的世界の接触相手と、静的または運動学的の剛体は逆質量も逆慣性も零であるため、衝撃を受けても運動状態が変わらない。
//! 枝を分けずに同じ式へ通せるのはそのためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

use blitz_math::{ローカル, ワールド, 位置, 変位, 方向, 衝撃, 逆キログラム, 速度};

use super::super::contact_projection_participant::接触の射影に参加する点;
use crate::rigid_body::運動状態;
use crate::rigid_xpbd::姿勢自由度の参加者;

/// 速度段階の片側。接触点と、そこへ衝撃が掛かる参加者の運動状態を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 速度段階の参加点 {
    接触点: 接触の射影に参加する点,
    運動状態: 運動状態,
}

impl 速度段階の参加点 {
    /// 剛体の側。細分の反復を終えた配置を持つ参加者と、再構成した運動状態と、重心局所の接触点である。
    pub fn 剛体から生成する(
        参加者: 姿勢自由度の参加者, 局所接触点: 変位<ローカル>, 運動状態: 運動状態
    ) -> Self {
        Self {
            接触点: 接触の射影に参加する点::剛体の局所点から生成する(参加者, 局所接触点),
            運動状態,
        }
    }

    /// 静的世界の接触相手の側。速度を持たない参加者である。
    pub fn 静的世界の固定点から生成する(世界位置: 位置<ワールド>) -> Self {
        Self {
            接触点: 接触の射影に参加する点::静的世界の固定点から生成する(世界位置),
            運動状態: 運動状態::静止(),
        }
    }

    /// 衝撃を適用した後の運動状態。台帳へ書き戻すのはこの値である。
    pub fn 運動状態(&self) -> 運動状態 {
        self.運動状態
    }

    pub(super) fn 動かせないか(&self) -> bool {
        self.接触点.動かせないか()
    }

    // 接触点そのものが持つ速度 v + ω × r。相対速度はこの2つの差である。
    pub(super) fn 接触点の速度(&self) -> 速度<ワールド> {
        self.運動状態.並進速度() + self.運動状態.角速度().腕の先の速度を求める(self.接触点.腕())
    }

    pub(super) fn 一般化逆質量(&self, 向き: 方向<ワールド>) -> 逆キログラム {
        self.接触点.一般化逆質量(向き)
    }

    // 衝撃 P を接触点へ受けた後の参加点。v ← v + w P、ω ← ω + I⁻¹ (r × P) であり、配置は変わらない。
    pub(super) fn 衝撃を受けた参加点(&self, 衝撃: 衝撃<ワールド>) -> Self {
        let 参加者: &姿勢自由度の参加者 = self.接触点.参加者();
        let 回転衝撃 = self.接触点.腕().腕に掛かる衝撃の回転衝撃(衝撃);
        Self {
            接触点: self.接触点,
            運動状態: 運動状態::生成する(
                self.運動状態.並進速度() + 衝撃 * 参加者.逆質量(),
                self.運動状態.角速度() + 参加者.ワールドの逆慣性().回転衝撃を角速度へ写す(回転衝撃),
            ),
        }
    }
}
