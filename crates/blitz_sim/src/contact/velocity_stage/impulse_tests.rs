//! 速度段階の動摩擦の試験(判断14)。担当するのは2つの性質を固定することである。上限 μ_d λ_n ÷ h が効くのは
//! 接線の相対速度を零にする衝撃より小さいときだけであること、滑走中と印されていない接触点へ動摩擦を適用しないことである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

#![allow(clippy::unwrap_used)]

use blitz_math::ニュートン秒;

use super::impulse_fixture::{刻み幅の秒, 適用する};
use super::result::接触の速度段階の結果;

#[test]
fn 動摩擦の上限が効くのは接線の相対速度を零にする衝撃より小さいときだけである() {
    // 有効逆質量1のとき、接線の相対速度を零にする衝撃の大きさは接線の速さに等しい。上限は μ_d λ_n ÷ h である。
    let 上限が効く = 適用する(2.0, 0.0, 0.5, 0.001, 0.0, true);
    let 接触の速度段階の結果::衝撃を適用した {
        動摩擦の衝撃,
        適用後のaの運動状態,
        ..
    } = 上限が効く
    else {
        panic!("衝撃を適用した枝が返っていない");
    };
    assert!((動摩擦の衝撃.値() - 0.5 * 0.001 / 刻み幅の秒).abs() < 1.0e-4);
    assert!(適用後のaの運動状態.並進速度().x().値() > 1.5, "上限を超えて減速している");
    let 速度が零になる = 適用する(0.1, 0.0, 0.5, 1.0, 0.0, true);
    let 接触の速度段階の結果::衝撃を適用した {
        動摩擦の衝撃,
        適用後のaの運動状態,
        ..
    } = 速度が零になる
    else {
        panic!("衝撃を適用した枝が返っていない");
    };
    assert!((動摩擦の衝撃.値() - 0.1).abs() < 1.0e-6);
    assert!(適用後のaの運動状態.並進速度().x().値().abs() < 1.0e-6, "接線の相対速度が零にならない");
}

#[test]
fn 滑走中と印されていない接触点へ動摩擦を適用しない() {
    let 結果 = 適用する(2.0, 0.0, 0.5, 1.0, 0.0, false);
    let 接触の速度段階の結果::衝撃を適用した {
        動摩擦の衝撃,
        適用後のaの運動状態,
        ..
    } = 結果
    else {
        panic!("衝撃を適用した枝が返っていない");
    };
    assert_eq!(動摩擦の衝撃, ニュートン秒::生成する(0.0));
    assert!((適用後のaの運動状態.並進速度().x().値() - 2.0).abs() < 1.0e-6);
}
