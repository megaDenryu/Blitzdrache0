//! 速度段階の衝撃の試験が共有する材料(判断14)。担当するのは、重心そのものが接触点である剛体の側と、
//! 静的世界の固定点の側と、速度段階と接触物性と条件を組むことである。腕を零にするのは、一般化逆質量が
//! 逆質量1に等しくなり、衝撃の大きさを手計算で追えるようにするためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{
    キログラム, キログラム平方メートル, クォータニオン, メートル, メートル毎秒, ワールド, 位置, 変位, 方向, 秒, 角速度, 逆キログラム, 速度,
};

use super::super::contact_property::接触物性;
use super::super::friction_coefficient::摩擦係数;
use super::super::restitution_coefficient::反発係数;
use super::condition::速度段階の接触点の条件;
use super::participant::速度段階の参加点;
use super::result::接触の速度段階の結果;
use super::stage::接触の速度段階;
use crate::rigid_body::{主慣性, 主慣性と主軸, 姿勢, 質量特性, 運動状態, 配置};
use crate::rigid_xpbd::姿勢自由度の参加者;
use crate::xpbd::{ラグランジュ乗数, 刻み幅};

pub(super) const 刻み幅の秒: f32 = 1.0 / 480.0;
pub(super) const 抑制の閾値: f32 = 0.05;
pub(super) const 反発係数の値: f32 = 0.8;

pub(super) fn 下向きの接触法線() -> 方向<ワールド> {
    方向::生成する(0.0, -1.0, 0.0).unwrap()
}

pub(super) fn 速度段階(動摩擦係数: f32) -> (接触の速度段階, 接触物性) {
    let 段階 = 接触の速度段階::生成する(刻み幅::生成する(秒::生成する(刻み幅の秒)).unwrap(), メートル毎秒::生成する(抑制の閾値));
    let 物性 = 接触物性::生成する(
        摩擦係数::生成する(動摩擦係数).unwrap(),
        摩擦係数::生成する(動摩擦係数).unwrap(),
        反発係数::生成する(反発係数の値).unwrap(),
    )
    .unwrap();
    (段階, 物性)
}

// 重心そのものが接触点である剛体。腕が零であるため一般化逆質量は逆質量1に等しい。
pub(super) fn 重心が接触点の剛体(並進速度: 速度<ワールド>) -> 速度段階の参加点 {
    let 慣性 = キログラム平方メートル::生成する(1.0);
    let 質量特性 = 質量特性::生成する(
        キログラム::生成する(1.0).unwrap(),
        変位::零(),
        主慣性と主軸::生成する(主慣性::生成する(慣性, 慣性, 慣性), クォータニオン::軸が一致する回転()).unwrap(),
    )
    .unwrap();
    let 配置 = 配置::生成する(
        位置::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0)),
        姿勢::恒等(),
    );
    速度段階の参加点::剛体から生成する(
        姿勢自由度の参加者::動的(配置, &質量特性),
        変位::零(),
        運動状態::生成する(並進速度, 角速度::零()),
    )
}

pub(super) fn 静的世界の接触点() -> 速度段階の参加点 {
    速度段階の参加点::静的世界の固定点から生成する(位置::生成する(
        メートル::生成する(0.0),
        メートル::生成する(0.0),
        メートル::生成する(0.0),
    ))
}

pub(super) fn 世界の速度(x: f32, y: f32, z: f32) -> 速度<ワールド> {
    速度::成分から生成する(メートル毎秒::生成する(x), メートル毎秒::生成する(y), メートル毎秒::生成する(z))
}

pub(super) fn 法線の乗数(値: f32) -> ラグランジュ乗数 {
    ラグランジュ乗数::長さを逆質量で割って生成する(メートル::生成する(値), 逆キログラム::生成する(1.0).unwrap())
}

pub(super) fn 条件(
    接触物性: 接触物性, 法線の乗数の値: f32, 予測の前の法線相対速度: f32, 滑走中か: bool
) -> 速度段階の接触点の条件 {
    速度段階の接触点の条件::生成する(
        下向きの接触法線(),
        接触物性,
        法線の乗数(法線の乗数の値),
        メートル毎秒::生成する(予測の前の法線相対速度),
        滑走中か,
    )
}

pub(super) fn 適用する(
    接線の速さ: f32,
    法線の速さ: f32,
    動摩擦係数: f32,
    法線の乗数の値: f32,
    予測の前の法線相対速度: f32,
    滑走中か: bool,
) -> 接触の速度段階の結果 {
    let (段階, 物性) = 速度段階(動摩擦係数);
    段階.一点へ適用する(
        重心が接触点の剛体(世界の速度(接線の速さ, 法線の速さ, 0.0)),
        静的世界の接触点(),
        条件(物性, 法線の乗数の値, 予測の前の法線相対速度, 滑走中か),
    )
}
