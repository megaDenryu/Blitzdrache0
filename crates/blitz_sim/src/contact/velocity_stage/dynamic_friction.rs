//! 速度段階の動摩擦(判断14)。滑走中と印された接触点だけへ、接線の相対速度を止める向きの衝撃を与える。
//! 反発と分けているのは、動摩擦が1細分に1度だけ与える量であるのに対し、反発は法線の条件が揃うまで巡回させる量だからである。
//!   t̂ = v_t ÷ |v_t|、j_t = min(μ_d λ_n ÷ h, |v_t| ÷ w̃_t)、P = −j_t t̂
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

use blitz_math::{ニュートン秒, 衝撃};

use super::condition::速度段階の接触点の条件;
use super::participant::速度段階の参加点;
use super::stage::{両側へ与える, 接触の速度段階, 相対速度を求める, 衝撃を適用した後の両側};

impl 接触の速度段階 {
    /// 滑走中と印された接触点だけへ、接線の相対速度を止める向きの衝撃を与える。上限は μ_d λ_n ÷ h であり、
    /// 接線の相対速度を零にする衝撃 |v_t| ÷ w̃_t との小さい方を採る。
    pub(super) fn 動摩擦の衝撃を適用する(
        &self,
        a: 速度段階の参加点,
        b: 速度段階の参加点,
        条件: &速度段階の接触点の条件,
    ) -> 衝撃を適用した後の両側 {
        let 接線の相対速度 = 相対速度を求める(a, b).方向の成分を除く(条件.接触法線());
        let (true, Ok(接線の向き)) = (条件.滑走中か(), 接線の相対速度.単位方向()) else {
            return 衝撃を適用した後の両側 {
                a,
                b,
                衝撃の大きさ: ニュートン秒::生成する(0.0),
            };
        };
        let 有効逆質量 = a.一般化逆質量(接線の向き) + b.一般化逆質量(接線の向き);
        let 上限 = 条件.接触物性().動摩擦の衝撃の上限を求める(条件.法線のラグランジュ乗数(), self.刻み幅);
        let 接線の相対速度を零にする衝撃 = 接線の相対速度.長さ() / 有効逆質量;
        let 大きさ = if 上限 < 接線の相対速度を零にする衝撃 {
            上限
        } else {
            接線の相対速度を零にする衝撃
        };
        両側へ与える(a, b, 衝撃::方向へ生成する(接線の向き.逆を向く方向(), 大きさ), 大きさ)
    }
}
