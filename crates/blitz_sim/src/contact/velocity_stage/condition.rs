//! 速度段階が接触点1つを解くのに要る条件(判断14)。接触拘束が細分の終わりに組んで速度段階へ渡す。
//! 予測の前の法線相対速度をここへ入れるのは、反発が衝突前の速度を参照する現象であり、細分の反復を終えた後の速度からは
//! 復元できないためである。この値は細分の予測(外力による速度の更新の後、位置の補正の前)の時点で測る。
//! 滑走中の印は静止摩擦の解の状態が立てた値であり、動摩擦をその接触点へ効かせてよいかを決める。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14: 反発と動摩擦は速度段階で衝撃として1箇所ずつ適用し、低速の反発は零に落とす」

use blitz_math::{メートル毎秒, ワールド, 方向};

use super::super::contact_property::接触物性;
use crate::xpbd::ラグランジュ乗数;

/// 接触点1つの速度段階の条件。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 速度段階の接触点の条件 {
    接触法線: 方向<ワールド>,
    接触物性: 接触物性,
    法線のラグランジュ乗数: ラグランジュ乗数,
    予測の前の法線相対速度: メートル毎秒,
    滑走中か: bool,
}

impl 速度段階の接触点の条件 {
    /// 接触拘束が持つ値から組む。法線のラグランジュ乗数は、その細分で非貫通が実際に押し戻した値だけを渡す。
    pub fn 生成する(
        接触法線: 方向<ワールド>,
        接触物性: 接触物性,
        法線のラグランジュ乗数: ラグランジュ乗数,
        予測の前の法線相対速度: メートル毎秒,
        滑走中か: bool,
    ) -> Self {
        Self {
            接触法線,
            接触物性,
            法線のラグランジュ乗数,
            予測の前の法線相対速度,
            滑走中か,
        }
    }

    pub(super) fn 接触法線(&self) -> 方向<ワールド> {
        self.接触法線
    }

    pub(super) fn 接触物性(&self) -> 接触物性 {
        self.接触物性
    }

    pub(super) fn 法線のラグランジュ乗数(&self) -> ラグランジュ乗数 {
        self.法線のラグランジュ乗数
    }

    pub(super) fn 予測の前の法線相対速度(&self) -> メートル毎秒 {
        self.予測の前の法線相対速度
    }

    pub(super) fn 滑走中か(&self) -> bool {
        self.滑走中か
    }
}
