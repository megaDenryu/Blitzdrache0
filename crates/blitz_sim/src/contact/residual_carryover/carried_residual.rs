//! 持ち越す接線の残差: ある細分の終わりに、静止摩擦の行が零へ戻すべきだった錨からの接線変位のうち、その細分で
//! 閉じずに残った変位(判断24)。接触点1つにつき接平面上の2次元の変位であり、単位はメートルである。
//! 意図して残した許容差 δ の分と、擬似逆が捨てた向きと階数不足の分の両方を1つの量として持つ。細分の終わりの
//! 配置から測れるのが両者の和だけであり、2つを区別する必要があるのは擬似逆の受理条件の側だからである。
//! 「無し」を零の変位で表さないのは、零の残差(閉じ切った細分)と、持ち越しが破棄された細分を区別するためである。
//! 前者は残差の変化を差で求めてよく、後者は差そのものを零に置く。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

use blitz_math::{ワールド, 変位};

/// 接触点1つが1本の細分について持つ接線の残差。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 持ち越す接線の残差 {
    /// この細分にはこの接触点の静止摩擦の行が無く、閉じるべきだった変位も無い。
    無し,
    /// この細分の終わりに測った、閉じずに残った接平面上の変位。
    在る(変位<ワールド>),
}

impl 持ち越す接線の残差 {
    /// 測った変位から作る。接線平面へ落とすのは呼び出し側の仕事である(錨の差から法線の成分を除いた値を渡す)。
    pub fn 測った変位から生成する(接線の残差: 変位<ワールド>) -> Self {
        Self::在る(接線の残差)
    }

    /// 前の細分から持ち込んだ残差と、この細分の終わりに測った残差の差 s_{n+1} − s_n。
    /// どちらかが無しなら差は無い。速度から除くのは残差そのものではなくこの差である(判断24)。
    /// 定常で保持している接触の残差は一定の偏りであり、一定の偏りは速度を生まないためである。
    pub fn 細分のあいだの変化(持ち込んだ: Self, 細分の終わり: Self) -> Option<変位<ワールド>> {
        match (持ち込んだ, 細分の終わり) {
            (Self::在る(前), Self::在る(今)) => Some(今 - 前),
            _ => None,
        }
    }

    /// 測った変位。無しの枝では読めない。計器と検査が読む口である。
    #[cfg(test)]
    pub fn 測った変位(&self) -> Option<変位<ワールド>> {
        match self {
            Self::無し => None,
            Self::在る(残差) => Some(*残差),
        }
    }
}
