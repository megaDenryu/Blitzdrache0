//! 剛体と剛体の接触拘束の静的な引数(判断11の表の左の行)。XPBD共通拘束基盤の判断4の3分割のうち、細分の間に変わらない側である。
//! 接触点を両剛体の重心局所座標で持つのは、細分の間に剛体が動いても現在の姿勢で貫通量を再評価するためである(判断12)。
//! 接触法線は生成した細分の間は固定であり、生成時の貫通量は履歴の対応付けと計器が読む記録である。
//! 欄を名前付きで持つのは、同じ型の値(2つの重心局所の接触点)が並ぶ組み立てで、位置による取り違えを起こさないためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use blitz_math::{ローカル, ワールド, 変位, 方向};

use super::contact_property::接触物性;
use super::feature_identity::接触の特徴の識別;
use super::non_penetration::非貫通の解き方;
use super::penetration_depth::貫通量;
use crate::rigid_body::剛体の識別子;

/// 剛体と剛体の接触点1つが持つ、細分の間に変わらない値。接触法線は剛体aから剛体bへ向かう。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 剛体と剛体の接触拘束の引数 {
    pub 剛体a: 剛体の識別子,
    pub 剛体b: 剛体の識別子,
    pub 局所接触点a: 変位<ローカル>,
    pub 局所接触点b: 変位<ローカル>,
    pub 接触法線: 方向<ワールド>,
    pub 生成時の貫通量: 貫通量,
    pub 特徴の識別: 接触の特徴の識別,
    pub 接触物性: 接触物性,
    pub 解き方: 非貫通の解き方,
}
