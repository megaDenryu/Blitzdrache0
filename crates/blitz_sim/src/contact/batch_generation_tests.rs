fn 上下の箱のバッチを作る(
    混合則: &混合則,
    上の姿勢: 姿勢,
    接触点集合: &接触点集合<直方体どうしの接触の特徴の対>,
) -> 接触拘束の二つのバッチ {
    let (上の配置, 下の配置) = (上の箱の配置(上の姿勢), 下の箱の配置());
    let mut 台帳 = 剛体の台帳::空();
    let 上 = 接触に参加する剛体を作る(台帳へ登録する(&mut 台帳, 上の配置), 上の配置);
    let 下 = 接触に参加する剛体を作る(台帳へ登録する(&mut 台帳, 下の配置), 下の配置);
    let mut 組み立て = 接触拘束のバッチの組み立て::生成する(混合則, コンプライアンス::硬い(), 試験の刻み幅(), 1);
    組み立て.剛体どうしの接触点集合を積む(&上, &下, 接触点集合).unwrap();
    組み立て.二つのバッチを組み立てる()
}

// 世界へ戻した点が、接触点集合が返した点と3成分とも一致するか。倍精度から単精度へ狭めた誤差だけを許す。
fn 世界へ戻した点が接触点と一致するか(戻した: 位置<ワールド>, 点: 形の局所座標の位置) -> bool {
    [
        f64::from(戻した.x().値()) - 点.xのメートル(),
        f64::from(戻した.y().値()) - 点.yのメートル(),
        f64::from(戻した.z().値()) - 点.zのメートル(),
    ]
    .iter()
    .all(|差| 差.abs() < 1.0e-6)
}

fn 局所点が世界へ戻るか(
    接触点集合: &接触点集合<直方体どうしの接触の特徴の対>,
    バッチ: &接触拘束の二つのバッチ,
    上の配置: &配置,
    下の配置: &配置,
) -> bool {
    接触点集合.接触点を順に並べる().zip(バッチ.剛体どうし()).all(|(接触点, 拘束)| {
        世界へ戻した点が接触点と一致するか(上の配置.局所点の世界位置(拘束.引数().局所接触点a), 接触点.第1の形の上の位置())
            && 世界へ戻した点が接触点と一致するか(下の配置.局所点の世界位置(拘束.引数().局所接触点b), 接触点.第2の形の上の位置())
    })
}

#[test]
fn 面どうしの接触点が全部拘束として残る() {
    let 混合則 = 単一の材質の混合則();
    let 接触点集合 = 上下の箱の接触点集合(姿勢::恒等());
    let バッチ = 上下の箱のバッチを作る(&混合則, 姿勢::恒等(), &接触点集合);
    assert_eq!(接触点集合.件数(), 4);
    assert_eq!(バッチ.剛体どうし().len(), 4);
    assert!(バッチ.剛体と静的世界().is_empty());
    let 全部が別の局所点を持つ = バッチ.剛体どうし().iter().enumerate().all(|(添字, 拘束)| {
        バッチ.剛体どうし()[添字 + 1..]
            .iter()
            .all(|他| 他.引数().局所接触点a != 拘束.引数().局所接触点a)
    });
    assert!(全部が別の局所点を持つ);
}

#[test]
fn 接触法線は第1の参加者から第2の参加者へ向く() {
    let 混合則 = 単一の材質の混合則();
    let 接触点集合 = 上下の箱の接触点集合(姿勢::恒等());
    let バッチ = 上下の箱のバッチを作る(&混合則, 姿勢::恒等(), &接触点集合);
    for 拘束 in バッチ.剛体どうし() {
        let 法線 = 拘束.引数().接触法線;
        assert!(法線.x().abs() < 1.0e-6 && 法線.z().abs() < 1.0e-6);
        assert!((法線.y() + 1.0).abs() < 1.0e-6);
        assert!((拘束.引数().生成時の貫通量.長さ().値() - 食い込み).abs() < 1.0e-6);
    }
}

#[test]
fn 姿勢が恒等でなくても局所点が世界へ戻る() {
    let 混合則 = 単一の材質の混合則();
    for 上の姿勢 in [姿勢::恒等(), 鉛直軸まわりに四分の一回した姿勢()] {
        let 接触点集合 = 上下の箱の接触点集合(上の姿勢);
        let バッチ = 上下の箱のバッチを作る(&混合則, 上の姿勢, &接触点集合);
        assert!(局所点が世界へ戻るか(
            &接触点集合,
            &バッチ,
            &上の箱の配置(上の姿勢),
            &下の箱の配置()
        ));
    }
}
