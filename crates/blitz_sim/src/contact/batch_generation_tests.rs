//! 剛体と剛体の接触拘束の生成の試験(判断11)。担当するのは3つの性質を固定することである。接触点集合の全部の点が
//! 拘束として残って1点へ潰れないこと、重心局所へ写した点を世界へ戻すと接触点集合の点と1e-6メートル以内で一致すること
//! (姿勢が恒等でない剛体でも成り立つこと)、接触法線が第1の参加者から第2の参加者へ向くことである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

