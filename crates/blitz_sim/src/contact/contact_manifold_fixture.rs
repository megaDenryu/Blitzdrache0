//! 直方体2つから実際の接触点集合を作る試験の材料。担当するのは、2つの形の運動から本番と同じ導出で接触生成の余白を
//! 求めることと、その余白で接触点集合の問い合わせを回すことである。
//! 接触点集合を手で組み立てず衝突数学層の問い合わせから作るのは、生成の工程が受け取る値の並びと不変条件
//! (第2の形の上の点は第1の形の上の点から法線の向きへ符号付き貫通量だけ戻った点である)を試験でも本物に保つためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_collision::contact_set::{
    二つの直方体の重なりの接触点集合, 外積の軸へ切り替える優位幅メートル, 接触点集合, 接触生成の余白メートル, 直方体どうしの接触の特徴の対,
    直方体どうしの接触点集合の問い合わせ,
};
use blitz_collision::shape::任意姿勢の直方体;

use super::contact_test_fixtures::試験の刻み幅;
use super::generation_margin::{
    接触生成の余白を導く形の運動, 細分の運動から接触生成の余白を導く, 細分の静穏の運動から外積の軸へ切り替える優位幅を導く,
};
use crate::rigid_body::運動状態;

/// 2つの形のこの細分の運動から、参照軸の選択が読む優位幅を導く。試験も本番と同じ導出を通す。
pub(super) fn 二つの形の静穏の運動から外積の軸へ切り替える優位幅を導く(
    第1: &任意姿勢の直方体,
    第1の運動状態: 運動状態,
    第2: &任意姿勢の直方体,
    第2の運動状態: 運動状態,
) -> 外積の軸へ切り替える優位幅メートル {
    細分の静穏の運動から外積の軸へ切り替える優位幅を導く(
        &接触生成の余白を導く形の運動::動く形から生成する(第1, 第1の運動状態),
        &接触生成の余白を導く形の運動::動く形から生成する(第2, 第2の運動状態),
        試験の刻み幅(),
    )
    .unwrap()
}

/// 2つの形のこの細分の運動から接触生成の余白を導く。試験も本番と同じ導出を通す。
pub(super) fn 二つの形の運動から接触生成の余白を導く(
    第1: &任意姿勢の直方体,
    第1の運動状態: 運動状態,
    第2: &任意姿勢の直方体,
    第2の運動状態: 運動状態,
) -> 接触生成の余白メートル {
    細分の運動から接触生成の余白を導く(
        &接触生成の余白を導く形の運動::動く形から生成する(第1, 第1の運動状態),
        &接触生成の余白を導く形の運動::動く形から生成する(第2, 第2の運動状態),
        試験の刻み幅(),
    )
    .unwrap()
}

pub(super) fn 直方体どうしの接触点集合を求める(
    第1: &任意姿勢の直方体,
    第2: &任意姿勢の直方体,
    余白: 接触生成の余白メートル,
) -> 接触点集合<直方体どうしの接触の特徴の対> {
    let 問い合わせ = 直方体どうしの接触点集合の問い合わせ::二つの直方体と余白と優位幅から生成する(
        第1,
        第2,
        余白,
        外積の軸へ切り替える優位幅メートル::優位幅を持たない(),
    );
    match 問い合わせ.二つの直方体の重なりの接触点集合を求める().unwrap() {
        二つの直方体の重なりの接触点集合::二つの直方体が重なっている(集合) => 集合,
        二つの直方体の重なりの接触点集合::二つの直方体は離れている => {
            panic!("試験の材料の2つの直方体が重なっていない")
        }
    }
}
