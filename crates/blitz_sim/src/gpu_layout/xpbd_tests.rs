//! 拘束グラフのGPU表現の検査: 点と拘束の1件のバイト数と並び、隣接表の2本の長さと1語の符号化がレイアウトの契約どおりであることを見る。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 位置, 逆キログラム};

use super::xpbd::{
    拘束1件のバイト数, 拘束の引数バイト列にする, 点1件のバイト数, 点の状態バイト列にする, 隣接の区間バイト列にする, 隣接の項目バイト列にする,
};
use crate::constraint_graph::{拘束グラフ, 添字付き距離拘束, 点ごとの拘束の隣接表, 点添字, 点自由度の初期状態};
use crate::xpbd::{コンプライアンス, 距離拘束の引数, 静止長};

fn 二点一拘束のグラフ() -> 拘束グラフ {
    let 点 = |x: f32, 逆質量: f32| {
        点自由度の初期状態::生成する(
            位置::<ワールド>::生成する(メートル::生成する(x), メートル::生成する(2.0), メートル::生成する(3.0)),
            逆キログラム::生成する(逆質量).unwrap(),
        )
    };
    let 引数 = 距離拘束の引数::生成する(
        静止長::生成する(メートル::生成する(1.5)).unwrap(),
        コンプライアンス::生成する(0.25).unwrap(),
    );
    拘束グラフ::生成する(
        vec![点(0.0, 0.0), 点(1.0, 4.0)],
        vec![添字付き距離拘束::生成する(点添字::生成する(0), 点添字::生成する(1), 引数).unwrap()],
    )
    .unwrap()
}

fn 単精度(バイト列: &[u8], 開始: usize) -> f32 {
    f32::from_le_bytes([バイト列[開始], バイト列[開始 + 1], バイト列[開始 + 2], バイト列[開始 + 3]])
}

fn 語(バイト列: &[u8], 開始: usize) -> u32 {
    u32::from_le_bytes([バイト列[開始], バイト列[開始 + 1], バイト列[開始 + 2], バイト列[開始 + 3]])
}

#[test]
fn 点は位置3成分と逆質量の16バイトである() {
    let バイト列 = 点の状態バイト列にする(&二点一拘束のグラフ());
    assert_eq!(バイト列.len(), 2 * 点1件のバイト数);
    assert_eq!(
        [単精度(&バイト列, 16), 単精度(&バイト列, 20), 単精度(&バイト列, 24), 単精度(&バイト列, 28)],
        [1.0, 2.0, 3.0, 4.0]
    );
}

#[test]
fn 拘束は両端の添字と静止長とコンプライアンスの16バイトである() {
    let バイト列 = 拘束の引数バイト列にする(&二点一拘束のグラフ());
    assert_eq!(バイト列.len(), 拘束1件のバイト数);
    assert_eq!((語(&バイト列, 0), 語(&バイト列, 4)), (0, 1));
    assert_eq!((単精度(&バイト列, 8), 単精度(&バイト列, 12)), (1.5, 0.25));
}

#[test]
fn 隣接表は区間の開始が点の数足す1語で項目が拘束の数の2倍語である() {
    let グラフ = 二点一拘束のグラフ();
    let 表 = 点ごとの拘束の隣接表::生成する(&グラフ);
    let 区間 = 隣接の区間バイト列にする(&表);
    let 項目 = 隣接の項目バイト列にする(&表);
    assert_eq!(区間.len(), (グラフ.点の数() + 1) * 4);
    assert_eq!(項目.len(), グラフ.拘束の数() * 2 * 4);
    assert_eq!([語(&区間, 0), 語(&区間, 4), 語(&区間, 8)], [0, 1, 2]);
    // 点0は拘束0のa側(0×2+0)、点1は拘束0のb側(0×2+1)である。
    assert_eq!([語(&項目, 0), 語(&項目, 4)], [0, 1]);
}
