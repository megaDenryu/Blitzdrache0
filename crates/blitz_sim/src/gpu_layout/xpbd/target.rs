//! 目標拘束のバッチのGPU表現(判断9)。静的な引数(点の添字とコンプライアンス)と、毎刻み書き換える入力(目標位置と有効)の初期値を別のバイト列にする。
//! 目標拘束の引数は1本8バイト(粒子添字u32 + コンプライアンスf32)、目標位置は1本16バイト(xyz f32 + 有効f32。有効は1.0、無効は0.0)である。
//! 有効を目標位置と同じ16バイトへ置くのは、掴むと離すの介入が目標位置と有効を1語の書き込みで着脱するためである(判断6)。
//! ラグランジュ乗数は距離拘束の乗数バッファの後ろへ続けて置き(1本4バイト)、その初期値は`ラグランジュ乗数の初期バイト列にする`が距離と目標の合計で作る。
//! blitz_renderの布の目標拘束のslangがこの並びで読む(バインディング表は`shaders/cloth_step.slang`の冒頭)。

use crate::constraint_graph::{目標拘束のバッチ, 目標拘束の有効};

pub const 目標拘束1件のバイト数: usize = 8;
pub const 目標位置1件のバイト数: usize = 16;

pub fn 目標拘束の引数バイト列にする(バッチ: &目標拘束のバッチ) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(バッチ.拘束の数() * 目標拘束1件のバイト数);
    for 拘束 in バッチ.拘束一覧() {
        バイト列.extend_from_slice(&拘束.粒子.値().to_le_bytes());
        バイト列.extend_from_slice(&拘束.引数.コンプライアンス.値().to_le_bytes());
    }
    バイト列
}

pub fn 目標位置の初期バイト列にする(バッチ: &目標拘束のバッチ) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(バッチ.拘束の数() * 目標位置1件のバイト数);
    for 目標 in バッチ.初期の目標一覧() {
        for 成分 in [目標.位置.x(), 目標.位置.y(), 目標.位置.z()] {
            バイト列.extend_from_slice(&成分.値().to_le_bytes());
        }
        let 有効 = match 目標.有効 {
            目標拘束の有効::有効 => 1.0f32,
            目標拘束の有効::無効 => 0.0f32,
        };
        バイト列.extend_from_slice(&有効.to_le_bytes());
    }
    バイト列
}
