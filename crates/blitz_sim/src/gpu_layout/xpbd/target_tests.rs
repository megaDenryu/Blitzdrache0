//! 目標拘束のGPU表現の検査: 引数の8バイトと目標位置の16バイトの並びと、有効が1.0と0.0で写ることを見る。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 位置};

use super::target::{
    目標位置1件のバイト数, 目標位置の初期バイト列にする, 目標拘束1件のバイト数, 目標拘束の引数バイト列にする
};
use crate::constraint_graph::{添字付き目標拘束, 点添字, 目標拘束のバッチ, 目標拘束の目標};
use crate::xpbd::{コンプライアンス, 目標拘束の引数};

fn 単精度(バイト列: &[u8], 開始: usize) -> f32 {
    f32::from_le_bytes([バイト列[開始], バイト列[開始 + 1], バイト列[開始 + 2], バイト列[開始 + 3]])
}

fn 語(バイト列: &[u8], 開始: usize) -> u32 {
    u32::from_le_bytes([バイト列[開始], バイト列[開始 + 1], バイト列[開始 + 2], バイト列[開始 + 3]])
}

fn 二本のバッチ() -> 目標拘束のバッチ {
    let 位置 = 位置::<ワールド>::生成する(メートル::生成する(1.0), メートル::生成する(2.0), メートル::生成する(3.0));
    let 柔らかい = 目標拘束の引数::生成する(コンプライアンス::生成する(0.25).unwrap());
    目標拘束のバッチ::生成する(
        8,
        vec![
            (
                添字付き目標拘束::生成する(点添字::生成する(5), 目標拘束の引数::硬い()),
                目標拘束の目標::有効な位置(位置),
            ),
            (
                添字付き目標拘束::生成する(点添字::生成する(7), 柔らかい),
                目標拘束の目標::無効な位置(位置),
            ),
        ],
    )
    .unwrap()
}

#[test]
fn 目標拘束の引数は粒子添字とコンプライアンスの8バイトである() {
    let バイト列 = 目標拘束の引数バイト列にする(&二本のバッチ());
    assert_eq!(バイト列.len(), 2 * 目標拘束1件のバイト数);
    assert_eq!((語(&バイト列, 0), 単精度(&バイト列, 4)), (5, 0.0));
    assert_eq!((語(&バイト列, 8), 単精度(&バイト列, 12)), (7, 0.25));
}

/// 反証: 有効を0.0以外の値で写すと、GPUの「0.0なら読まない」判定が無効の拘束を効かせる。
#[test]
fn 目標位置は3成分と有効の16バイトであり有効は1と0で写る() {
    let バイト列 = 目標位置の初期バイト列にする(&二本のバッチ());
    assert_eq!(バイト列.len(), 2 * 目標位置1件のバイト数);
    assert_eq!(
        [単精度(&バイト列, 0), 単精度(&バイト列, 4), 単精度(&バイト列, 8), 単精度(&バイト列, 12)],
        [1.0, 2.0, 3.0, 1.0]
    );
    assert_eq!(単精度(&バイト列, 28), 0.0);
}
