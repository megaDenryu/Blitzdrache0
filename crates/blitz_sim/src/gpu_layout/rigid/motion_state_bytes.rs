//! 剛体運動状態バッファ(64バイト)の書き手と読み手。語0〜2が重心位置、語4〜7が姿勢、語8〜10が並進速度、語12〜14が角速度であり、語3・11・15は詰め物である。
//! 静的な剛体は速度を持たないため速度と角速度を零で書く(読み手はそれを速度として返し、種別は実行状態バッファが持つ)。

use blitz_math::{メートル, メートル毎秒, ラジアン毎秒, ワールド, 位置, 角速度, 速度};

use super::error::剛体レイアウトエラー;
use super::word_reader::剛体のバイト列の読み手;
use super::{剛体運動状態1件のバイト数, 単精度3つと詰め物を書く, 単精度4つを書く};
use crate::rigid_body::{剛体, 姿勢, 運動状態, 配置};

/// 読み手が復元した1件。配置と運動状態を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 剛体運動状態の読み取り {
    pub 配置: 配置,
    pub 運動状態: 運動状態,
}

pub fn 剛体運動状態バイト列にする(剛体一覧: &[剛体]) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(剛体一覧.len() * 剛体運動状態1件のバイト数);
    for 剛体 in 剛体一覧 {
        let 位置 = 剛体.配置().重心の位置();
        単精度3つと詰め物を書く(&mut バイト列, [位置.x().値(), 位置.y().値(), 位置.z().値()]);
        単精度4つを書く(&mut バイト列, 剛体.配置().姿勢().境界用xyzw配列());
        let 速度 = 剛体.運動種別().速度().unwrap_or(運動状態::静止());
        let (v, ω) = (速度.並進速度(), 速度.角速度());
        単精度3つと詰め物を書く(&mut バイト列, [v.x().値(), v.y().値(), v.z().値()]);
        単精度3つと詰め物を書く(&mut バイト列, [ω.x().値(), ω.y().値(), ω.z().値()]);
    }
    バイト列
}

/// 長さ・位置と速度の有限性・姿勢の長さを検証して読む。
pub fn 剛体運動状態をバイト列から読む(
    バイト列: &[u8],
) -> Result<Vec<剛体運動状態の読み取り>, 剛体レイアウトエラー> {
    let 読み手 = 剛体のバイト列の読み手::生成する(バイト列, 剛体運動状態1件のバイト数)?;
    (0..読み手.件数())
        .map(|添字| {
            let [x, y, z] = 読み手.単精度3つ(添字, 0);
            if ![x, y, z].iter().all(|値| 値.is_finite()) {
                return Err(剛体レイアウトエラー::位置が非有限 { 添字 });
            }
            let [qx, qy, qz, qw] = 読み手.単精度4つ(添字, 4);
            let 姿勢 = 姿勢::生成する(qx, qy, qz, qw).map_err(|誤り| 剛体レイアウトエラー::姿勢を作れない { 添字, 誤り })?;
            let [vx, vy, vz] = 読み手.単精度3つ(添字, 8);
            let [ωx, ωy, ωz] = 読み手.単精度3つ(添字, 12);
            if ![vx, vy, vz, ωx, ωy, ωz].iter().all(|値| 値.is_finite()) {
                return Err(剛体レイアウトエラー::速度が非有限 { 添字 });
            }
            Ok(剛体運動状態の読み取り {
                配置: 配置::生成する(
                    位置::<ワールド>::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z)),
                    姿勢,
                ),
                運動状態: 運動状態::生成する(
                    速度::成分から生成する(メートル毎秒::生成する(vx), メートル毎秒::生成する(vy), メートル毎秒::生成する(vz)),
                    角速度::成分から生成する(ラジアン毎秒::生成する(ωx), ラジアン毎秒::生成する(ωy), ラジアン毎秒::生成する(ωz)),
                ),
            })
        })
        .collect()
}
