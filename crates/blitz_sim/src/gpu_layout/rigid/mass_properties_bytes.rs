//! 剛体質量特性バッファ(32バイト)の書き手と読み手。語0が逆質量、語1〜3が逆主慣性、語4〜7が主軸(xyzw)であり、詰め物は無い。
//! 原則不変の量であり、運動状態と別のバッファに置いて毎刻みの帯域に載せない(判断22)。

use blitz_math::{クォータニオン, ローカル, 主軸, 逆キログラム, 逆キログラム平方メートル};

use super::error::剛体レイアウトエラー;
use super::word_reader::剛体のバイト列の読み手;
use super::{剛体質量特性1件のバイト数, 単精度4つを書く};
use crate::rigid_body::剛体;

/// 読み手が復元した1件。解法が読む逆質量と逆主慣性と主軸だけを持ち、質量と重心のずれは持たない(GPUの反復が読まない)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 剛体質量特性の読み取り {
    pub 逆質量: 逆キログラム,
    pub 逆主慣性: [逆キログラム平方メートル; 3],
    pub 主軸: クォータニオン<主軸, ローカル>,
}

pub fn 剛体質量特性バイト列にする(剛体一覧: &[剛体]) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(剛体一覧.len() * 剛体質量特性1件のバイト数);
    for 剛体 in 剛体一覧 {
        let 質量特性 = 剛体.質量特性();
        let [a, b, c] = 質量特性.主慣性と主軸().逆主慣性();
        単精度4つを書く(&mut バイト列, [質量特性.逆質量().値(), a.値(), b.値(), c.値()]);
        単精度4つを書く(&mut バイト列, 質量特性.主慣性と主軸().主軸().成分());
    }
    バイト列
}

/// 長さ・逆質量と逆主慣性の非負と有限・主軸の長さを検証して読む。
pub fn 剛体質量特性をバイト列から読む(
    バイト列: &[u8],
) -> Result<Vec<剛体質量特性の読み取り>, 剛体レイアウトエラー> {
    let 読み手 = 剛体のバイト列の読み手::生成する(バイト列, 剛体質量特性1件のバイト数)?;
    (0..読み手.件数())
        .map(|添字| {
            let [w, a, b, c] = 読み手.単精度4つ(添字, 0);
            let 逆質量 = 逆キログラム::生成する(w).map_err(|誤り| 剛体レイアウトエラー::逆質量を作れない { 添字, 誤り })?;
            let mut 逆主慣性 = [逆キログラム平方メートル::零(); 3];
            for (軸番号, 値) in [a, b, c].into_iter().enumerate() {
                逆主慣性[軸番号] =
                    逆キログラム平方メートル::生成する(値).map_err(|誤り| 剛体レイアウトエラー::逆主慣性を作れない {
                        添字,
                        軸番号: 軸番号 + 1,
                        誤り,
                    })?;
            }
            let [qx, qy, qz, qw] = 読み手.単精度4つ(添字, 4);
            let 主軸 =
                クォータニオン::生成する(qx, qy, qz, qw).map_err(|誤り| 剛体レイアウトエラー::主軸を作れない { 添字, 誤り })?;
            Ok(剛体質量特性の読み取り {
                逆質量, 逆主慣性, 主軸
            })
        })
        .collect()
}
