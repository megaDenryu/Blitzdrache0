//! 剛体のGPUレイアウトの検査(判断22): 4つのバッファのバイト数が契約の値であること・書いた値を読み手が同じ値へ戻すこと(往復)・
//! 読み手が長さの不一致と長さが1でない姿勢と負の逆質量と範囲外の符号を型付きエラーで拒むことを固定する。
//! 1件のバイト数の写しはこのファイルが持ち、`cargo xtask conform`の定数の組が正本(`gpu_layout/rigid/mod.rs`)と突き合わせる。

#![allow(clippy::unwrap_used)]

use blitz_math::{キログラム, メートル, メートル毎秒, ラジアン毎秒, ワールド, 位置, 角速度, 速度};

use super::*;
use crate::rigid_body::{剛体の台帳, 姿勢, 質量特性, 運動状態, 運動種別, 配置};
use crate::rigid_xpbd::前の状態;

const 剛体運動状態1件のバイト数の写し: usize = 64;
const 剛体前状態1件のバイト数の写し: usize = 32;
const 剛体質量特性1件のバイト数の写し: usize = 32;
const 剛体実行状態1件のバイト数の写し: usize = 16;

pub(super) fn 三つの剛体の台帳() -> 剛体の台帳 {
    let 配置 = 配置::生成する(
        位置::<ワールド>::生成する(メートル::生成する(1.0), メートル::生成する(2.0), メートル::生成する(3.0)),
        姿勢::生成する(0.0, std::f32::consts::FRAC_1_SQRT_2, 0.0, std::f32::consts::FRAC_1_SQRT_2).unwrap(),
    );
    let 質量特性 = 質量特性::一様な箱(
        キログラム::生成する(2.0).unwrap(),
        メートル::生成する(1.0),
        メートル::生成する(2.0),
        メートル::生成する(3.0),
    )
    .unwrap();
    let 速度 = 運動状態::生成する(
        速度::成分から生成する(メートル毎秒::生成する(0.5), メートル毎秒::生成する(-1.0), メートル毎秒::生成する(0.0)),
        角速度::成分から生成する(ラジアン毎秒::生成する(0.0), ラジアン毎秒::生成する(3.0), ラジアン毎秒::生成する(0.25)),
    );
    let mut 台帳 = 剛体の台帳::空();
    台帳.登録する(配置, 質量特性, 運動種別::静的).unwrap();
    台帳.登録する(配置, 質量特性, 運動種別::運動学的で始める(速度)).unwrap();
    台帳.登録する(配置, 質量特性, 運動種別::動的で始める(速度)).unwrap();
    台帳
}

#[test]
fn 四つのバッファのバイト数は契約の値であり往復で同じ値へ戻る() {
    let 台帳 = 三つの剛体の台帳();
    let 剛体一覧 = 台帳.剛体一覧();
    let 運動状態 = 剛体運動状態バイト列にする(剛体一覧);
    assert_eq!(運動状態.len(), 3 * 剛体運動状態1件のバイト数の写し);
    let 読み取り = 剛体運動状態をバイト列から読む(&運動状態).unwrap();
    assert_eq!(読み取り[2].配置, *剛体一覧[2].配置());
    assert_eq!(読み取り[2].運動状態, 剛体一覧[2].速度().unwrap());
    assert_eq!(読み取り[0].運動状態, 運動状態::静止(), "静的な剛体の速度は零で写る");
    let 前 = [前の状態::配置から保存する(剛体一覧[0].配置())];
    let 前状態 = 剛体前状態バイト列にする(&前);
    assert_eq!(前状態.len(), 剛体前状態1件のバイト数の写し);
    assert_eq!(剛体前状態をバイト列から読む(&前状態).unwrap(), 前);
    let 質量特性 = 剛体質量特性バイト列にする(剛体一覧);
    assert_eq!(質量特性.len(), 3 * 剛体質量特性1件のバイト数の写し);
    let 読み取り = 剛体質量特性をバイト列から読む(&質量特性).unwrap();
    assert_eq!(読み取り[1].逆質量, 剛体一覧[1].質量特性().逆質量());
    assert_eq!(読み取り[1].逆主慣性, 剛体一覧[1].質量特性().主慣性と主軸().逆主慣性());
    assert_eq!(読み取り[1].主軸, *剛体一覧[1].質量特性().主慣性と主軸().主軸());
    let 実行状態 = 剛体実行状態バイト列にする(剛体一覧);
    assert_eq!(実行状態.len(), 3 * 剛体実行状態1件のバイト数の写し);
    let 読み取り = 剛体実行状態をバイト列から読む(&実行状態).unwrap();
    assert_eq!(
        読み取り.iter().map(|件| 件.運動種別).collect::<Vec<_>>(),
        [運動種別の符号::静的, 運動種別の符号::運動学的, 運動種別の符号::動的]
    );
    assert!(読み取り.iter().all(|件| 件.実行状態.起きているか()));
}

// 反証: 検証を外すと、長さが1でない姿勢・負の逆質量・範囲外の符号がGPUの読み出しへそのまま流れる。
#[test]
fn 読み手は長さの不一致と不正な姿勢と負の逆質量と範囲外の符号を拒む() {
    let 台帳 = 三つの剛体の台帳();
    let mut 運動状態 = 剛体運動状態バイト列にする(台帳.剛体一覧());
    assert!(matches!(
        剛体運動状態をバイト列から読む(&運動状態[..70]),
        Err(剛体レイアウトエラー::バイト数が1件の倍数でない { .. })
    ));
    運動状態[28..32].copy_from_slice(&2.0f32.to_le_bytes());
    assert!(matches!(
        剛体運動状態をバイト列から読む(&運動状態),
        Err(剛体レイアウトエラー::姿勢を作れない { 添字: 0, .. })
    ));
    let mut 質量特性 = 剛体質量特性バイト列にする(台帳.剛体一覧());
    質量特性[32..36].copy_from_slice(&(-1.0f32).to_le_bytes());
    assert!(matches!(
        剛体質量特性をバイト列から読む(&質量特性),
        Err(剛体レイアウトエラー::逆質量を作れない { 添字: 1, .. })
    ));
    let mut 実行状態 = 剛体実行状態バイト列にする(台帳.剛体一覧());
    実行状態[32..36].copy_from_slice(&7u32.to_le_bytes());
    assert!(matches!(
        剛体実行状態をバイト列から読む(&実行状態),
        Err(剛体レイアウトエラー::運動種別の符号が範囲外 { 添字: 2, 符号: 7 })
    ));
}
