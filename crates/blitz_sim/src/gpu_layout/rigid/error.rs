//! 剛体のバイト列を読む側が拒む内容。長さの不一致・非有限の位置・長さが1でない姿勢・負や非有限の逆質量と逆主慣性・主軸の不正・符号の範囲外が枝である。

use thiserror::Error;

use crate::rigid_body::姿勢エラー;

#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 剛体レイアウトエラー {
    #[error("バイト列の長さ{バイト数}が1件{一件のバイト数}バイトの倍数でない")]
    バイト数が1件の倍数でない { バイト数: usize, 一件のバイト数: usize },
    #[error("{添字}件目の位置の成分が有限値でない")]
    位置が非有限 { 添字: usize },
    #[error("{添字}件目の速度または角速度の成分が有限値でない")]
    速度が非有限 { 添字: usize },
    #[error("{添字}件目の姿勢を作れない: {誤り}")]
    姿勢を作れない { 添字: usize, 誤り: 姿勢エラー },
    #[error("{添字}件目の逆質量を作れない: {誤り}")]
    逆質量を作れない { 添字: usize, 誤り: blitz_math::質量エラー },
    #[error("{添字}件目の逆主慣性の第{軸番号}成分を作れない: {誤り}")]
    逆主慣性を作れない {
        添字: usize,
        軸番号: usize,
        誤り: blitz_math::質量エラー,
    },
    #[error("{添字}件目の主軸を作れない: {誤り}")]
    主軸を作れない {
        添字: usize, 誤り: blitz_math::クォータニオンエラー
    },
    #[error("{添字}件目の運動種別の符号{符号}が0(静的)・1(運動学的)・2(動的)のいずれでもない")]
    運動種別の符号が範囲外 { 添字: usize, 符号: u32 },
    #[error("{添字}件目の実行状態の符号{符号}が0(休止している)・1(起きている)のいずれでもない")]
    実行状態の符号が範囲外 { 添字: usize, 符号: u32 },
}
