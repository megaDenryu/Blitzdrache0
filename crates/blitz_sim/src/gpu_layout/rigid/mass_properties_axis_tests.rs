//! 質量特性の読み手が主軸に課す検査の反証(判断22): 非数・無限大・長さ2・長さ0の主軸をそれぞれ型付きエラーで拒み、
//! 単精度の丸めの範囲(1e-4以内)のずれは受理することを固定する。検証を外すと、GPUの出力の非数が逆慣性テンソルへ入って解法の全体が非数になる。

#![allow(clippy::unwrap_used)]

use blitz_math::クォータニオン;

use super::rigid_tests::三つの剛体の台帳;
use super::*;

// 0件目の主軸(語4〜7)を指定の4成分へ差し替えて読む。
fn 主軸を差し替えて読む(元: &[u8], 成分: [f32; 4]) -> Result<Vec<剛体質量特性の読み取り>, 剛体レイアウトエラー> {
    let mut 質量特性 = 元.to_vec();
    for (語番号, 値) in 成分.into_iter().enumerate() {
        let 開始 = 16 + 語番号 * 4;
        質量特性[開始..開始 + 4].copy_from_slice(&値.to_le_bytes());
    }
    剛体質量特性をバイト列から読む(&質量特性)
}

#[test]
fn 読み手は非数と無限大と長さ2と長さ0の主軸を拒み丸めの範囲のずれは受理する() {
    let 台帳 = 三つの剛体の台帳();
    let 元 = 剛体質量特性バイト列にする(台帳.剛体一覧());
    assert!(matches!(
        主軸を差し替えて読む(&元, [f32::NAN, 0.0, 0.0, 1.0]),
        Err(剛体レイアウトエラー::主軸が非有限 { 添字: 0, .. })
    ));
    assert!(matches!(
        主軸を差し替えて読む(&元, [0.0, f32::INFINITY, 0.0, 1.0]),
        Err(剛体レイアウトエラー::主軸が非有限 { 添字: 0, .. })
    ));
    assert!(matches!(
        主軸を差し替えて読む(&元, [0.0, 0.0, 0.0, 2.0]),
        Err(剛体レイアウトエラー::主軸が単位長でない { 添字: 0, .. })
    ));
    assert!(matches!(
        主軸を差し替えて読む(&元, [0.0, 0.0, 0.0, 0.0]),
        Err(剛体レイアウトエラー::主軸が単位長でない { 添字: 0, .. })
    ));
    let 読み取り = 主軸を差し替えて読む(&元, [0.0, 0.0, 0.0, 1.0 + 5.0e-5]).unwrap();
    assert_eq!(読み取り[0].主軸, クォータニオン::軸が一致する回転());
}
