//! 剛体前状態バッファ(32バイト)の書き手と読み手。語0〜2が前の重心位置、語4〜7が前の姿勢であり、語3は詰め物である。
//! 細分の予測が保存する前の状態(判断8)の写しであり、速度の再構成(判断9)がGPUでもこれを読む。

use blitz_math::{メートル, ワールド, 位置};

use super::error::剛体レイアウトエラー;
use super::word_reader::剛体のバイト列の読み手;
use super::{剛体前状態1件のバイト数, 単精度3つと詰め物を書く, 単精度4つを書く};
use crate::rigid_body::{姿勢, 配置};
use crate::rigid_xpbd::前の状態;

pub fn 剛体前状態バイト列にする(前の状態一覧: &[前の状態]) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(前の状態一覧.len() * 剛体前状態1件のバイト数);
    for 前 in 前の状態一覧 {
        let 位置 = 前.重心の位置();
        単精度3つと詰め物を書く(&mut バイト列, [位置.x().値(), 位置.y().値(), 位置.z().値()]);
        単精度4つを書く(&mut バイト列, 前.姿勢().境界用xyzw配列());
    }
    バイト列
}

/// 長さ・位置の有限性・姿勢の長さを検証して読む。
pub fn 剛体前状態をバイト列から読む(バイト列: &[u8]) -> Result<Vec<前の状態>, 剛体レイアウトエラー> {
    let 読み手 = 剛体のバイト列の読み手::生成する(バイト列, 剛体前状態1件のバイト数)?;
    (0..読み手.件数())
        .map(|添字| {
            let [x, y, z] = 読み手.単精度3つ(添字, 0);
            if ![x, y, z].iter().all(|値| 値.is_finite()) {
                return Err(剛体レイアウトエラー::位置が非有限 { 添字 });
            }
            let [qx, qy, qz, qw] = 読み手.単精度4つ(添字, 4);
            let 姿勢 = 姿勢::生成する(qx, qy, qz, qw).map_err(|誤り| 剛体レイアウトエラー::姿勢を作れない { 添字, 誤り })?;
            let 位置 = 位置::<ワールド>::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z));
            Ok(前の状態::配置から保存する(&配置::生成する(位置, 姿勢)))
        })
        .collect()
}
