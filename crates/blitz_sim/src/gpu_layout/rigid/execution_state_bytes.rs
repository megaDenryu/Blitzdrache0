//! 剛体実行状態バッファ(16バイト)の書き手と読み手。語0が運動種別の符号(0=静的・1=運動学的・2=動的)、語1が起きているか(1=起きている・0=休止している)、語2・3は詰め物である。
//! 符号の対応はここが正本であり、GPUの写し(Issue #43)は同じ値で書く。

use super::error::剛体レイアウトエラー;
use super::word_reader::剛体のバイト列の読み手;
use super::剛体実行状態1件のバイト数;
use crate::rigid_body::{剛体, 実行状態, 運動種別};

/// 運動種別の枝だけを表す符号。状態(速度・蓄積器)は運動状態バッファと台帳が持つため、ここでは枝の区別だけを運ぶ。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 運動種別の符号 {
    静的,
    運動学的,
    動的,
}

impl 運動種別の符号 {
    fn 語(self) -> u32 {
        match self {
            Self::静的 => 0,
            Self::運動学的 => 1,
            Self::動的 => 2,
        }
    }

    fn 語から読む(添字: usize, 符号: u32) -> Result<Self, 剛体レイアウトエラー> {
        match 符号 {
            0 => Ok(Self::静的),
            1 => Ok(Self::運動学的),
            2 => Ok(Self::動的),
            _ => Err(剛体レイアウトエラー::運動種別の符号が範囲外 { 添字, 符号 }),
        }
    }

    fn 運動種別から(運動種別: &運動種別) -> Self {
        match 運動種別 {
            運動種別::静的 => Self::静的,
            運動種別::運動学的 { .. } => Self::運動学的,
            運動種別::動的 { .. } => Self::動的,
        }
    }
}

/// 読み手が復元した1件。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 剛体実行状態の読み取り {
    pub 運動種別: 運動種別の符号,
    pub 実行状態: 実行状態,
}

pub fn 剛体実行状態バイト列にする(剛体一覧: &[剛体]) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(剛体一覧.len() * 剛体実行状態1件のバイト数);
    for 剛体 in 剛体一覧 {
        let 起きているか: u32 = match 剛体.実行状態() {
            実行状態::起きている { .. } => 1,
            実行状態::休止している => 0,
        };
        for 語 in [運動種別の符号::運動種別から(剛体.運動種別()).語(), 起きているか, 0, 0] {
            バイト列.extend_from_slice(&語.to_le_bytes());
        }
    }
    バイト列
}

/// 長さと2つの符号の範囲を検証して読む。
pub fn 剛体実行状態をバイト列から読む(
    バイト列: &[u8],
) -> Result<Vec<剛体実行状態の読み取り>, 剛体レイアウトエラー> {
    let 読み手 = 剛体のバイト列の読み手::生成する(バイト列, 剛体実行状態1件のバイト数)?;
    (0..読み手.件数())
        .map(|添字| {
            let 運動種別 = 運動種別の符号::語から読む(添字, 読み手.語(添字, 0))?;
            let 実行状態 = match 読み手.語(添字, 1) {
                1 => 実行状態::休止したことがなく起きている(),
                0 => 実行状態::休止している,
                符号 => return Err(剛体レイアウトエラー::実行状態の符号が範囲外 { 添字, 符号 }),
            };
            Ok(剛体実行状態の読み取り { 運動種別, 実行状態 })
        })
        .collect()
}
