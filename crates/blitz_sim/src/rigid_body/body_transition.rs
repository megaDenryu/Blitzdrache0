//! 剛体の状態の変更(判断7・判断18)。
//! 運動種別の遷移や休止・起床・静穏の連続細分数の更新を1つの列挙で表し、剛体自身のメソッドへ渡す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断7」「判断18」。

use super::motion_state::運動状態;
use super::placement::配置;
use super::wake_reason::休止から起きた理由;

/// 剛体の運動種別・配置・実行状態・静穏の連続細分数を一括して更新する操作(判断7・18)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 剛体の状態の変更 {
    動的に遷移する { 初速: 運動状態 },
    運動学的に遷移する { 次の配置: 配置, 導出速度: 運動状態 },
    静的に遷移する,
    休止させる,
    起こす { 理由: 休止から起きた理由 },
    静穏の連続細分数を進める,
    静穏の連続細分数を零にする,
}
