//! 静穏の継続時間: 動的剛体が連続して静穏である物理時間(判断18)。島の全剛体でこの時間が閾値に達すると島が休止する。
//! 細分の個数でなく物理時間で持つのは、細分数という解法品質の設定を変えただけで休止までの物理時間が変わってはならないためである。
//! 静穏の判定は細分ごとに行われるため、この時間は静穏な細分の刻み幅を積んで進み、静穏でない細分1本で零へ戻る。

use blitz_math::秒;

#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 静穏の継続時間(秒);

impl 静穏の継続時間 {
    /// 起きた直後、または静穏でない細分を挟んだ直後の値。
    pub fn 零() -> Self {
        Self(秒::生成する(0.0))
    }

    pub fn 値(&self) -> 秒 {
        self.0
    }

    /// 静穏な細分を1本通過したときの値。その細分の刻み幅ぶんだけ進む。
    pub fn 一細分ぶん進める(&self, 細分の刻み幅: 秒) -> Self {
        Self(self.0 + 細分の刻み幅)
    }

    /// 休止と判定する連続静穏の時間へ達したか。
    pub fn 閾値に達したか(&self, 閾値: 秒) -> bool {
        self.0 >= 閾値
    }
}
