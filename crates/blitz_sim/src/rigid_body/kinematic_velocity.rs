//! 運動学的剛体の速度導出(判断7)。
//! 外から与えた次の配置 (x', q') と現在の配置 (x, q) から並進速度と角速度を導く。
//! 回転は Δq = q' ⊗ q⁻¹ の対数写像であり、1刻みの回転量が π/2 [rad] を超える指定は型付きエラーで拒む。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断7: 運動種別の遷移は台帳の専用の操作であり、遷移後の状態は一意に決まる」

use std::f32::consts::FRAC_PI_2;

use blitz_math::{ラジアン, 秒};

use super::motion_state::運動状態;
use super::placement::配置;
use super::transition_error::運動種別の遷移エラー;

/// 1刻みで与えられる回転量の上限(π/2ラジアン)。半回転に近づくと対数写像が不定になるため拒む(判断7)。
pub fn 運動学的回転量の上限() -> ラジアン {
    ラジアン::生成する(FRAC_PI_2)
}

/// 現在の配置と次の刻みの配置、および基本刻み幅から運動学的剛体の運動状態を導出する。
pub fn 運動学的剛体の速度を導出する(
    現在の配置: &配置,
    次の配置: &配置,
    基本刻み: 秒,
) -> Result<運動状態, 運動種別の遷移エラー> {
    let 変位 = 次の配置.重心の位置() - 現在の配置.重心の位置();
    let 並進速度 = 変位 / 基本刻み;
    let 前の姿勢 = 現在の配置.姿勢();
    let 次の姿勢 = 次の配置.姿勢();
    let 差分回転 = 前の姿勢.逆回転().続けて回す(&次の姿勢.回転());
    let 回転ベクトル = 差分回転.対数写像で回転ベクトルへ();
    let 回転量 = 回転ベクトル.長さ();
    if 回転量 > 運動学的回転量の上限() {
        return Err(運動種別の遷移エラー::回転量が上限を超えている {
            回転量,
            上限: 運動学的回転量の上限(),
        });
    }
    let 角速度 = 回転ベクトル / 基本刻み;
    Ok(運動状態::生成する(並進速度, 角速度))
}
