//! 運動学的剛体の速度導出の検査(判断7)。
//! 1刻みの回転量がπ/2を超える配置指定のエラー検出と、対数写像による角速度の解析解一致を検証する。

use blitz_math::{クォータニオン, メートル, ラジアン, ローカル, ワールド, 位置, 回転ベクトル, 秒};

use super::kinematic_velocity::運動学的回転量の上限;
use super::orientation::姿勢;
use super::placement::配置;
use super::transition_error::運動種別の遷移エラー;

fn テスト用の位置() -> 位置<ワールド> {
    位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0))
}

#[test]
fn 回転量が二分のパイを超える運動学的指定は型付きエラーで拒絶される() {
    let 現在の配置 = 配置::生成する(テスト用の位置(), 姿勢::恒等());
    let 超過する回転 = 回転ベクトル::<ワールド>::成分から生成する(
        ラジアン::生成する(0.0),
        運動学的回転量の上限() + ラジアン::生成する(0.05),
        ラジアン::生成する(0.0),
    );
    let 次の姿勢 = 姿勢::回転から生成する(クォータニオン::<ローカル, ワールド>::回転ベクトルから生成する(
        超過する回転,
    ));
    let 次の配置 = 配置::生成する(テスト用の位置(), 次の姿勢);
    let 基本刻み = 秒::生成する(1.0 / 60.0);
    let 結果 = 現在の配置.次の配置へ移る運動学的な速度を導く(&次の配置, 基本刻み);
    match 結果 {
        Err(運動種別の遷移エラー::回転量が上限を超えている { 回転量, 上限 }) => {
            assert!(回転量 > 上限);
        }
        _ => panic!("回転量超過エラーが返るべき"),
    }
}

#[test]
fn 運動学的剛体の角速度が対数写像の式と解析解で一致する() {
    let 基本刻み = 秒::生成する(1.0 / 60.0);
    let 目標角速度 = 2.0_f32; // rad/s
    let 回転角 = 目標角速度 * 基本刻み.値();
    let 現在の配置 = 配置::生成する(テスト用の位置(), 姿勢::恒等());
    let 回転 =
        回転ベクトル::<ワールド>::成分から生成する(ラジアン::生成する(0.0), ラジアン::生成する(回転角), ラジアン::生成する(0.0));
    let 次の姿勢 = 姿勢::回転から生成する(クォータニオン::<ローカル, ワールド>::回転ベクトルから生成する(
        回転,
    ));
    let 次の配置 = 配置::生成する(テスト用の位置(), 次の姿勢);
    let Ok(運動状態) = 現在の配置.次の配置へ移る運動学的な速度を導く(&次の配置, 基本刻み) else {
        panic!("運動学的速度の導出に失敗した");
    };
    let 導出角速度 = 運動状態.角速度().y().値();
    let 誤差 = (導出角速度 - 目標角速度).abs();
    assert!(誤差 < 1.0e-5, "角速度の誤差が許容値を超えている: {誤差}");
}

#[test]
fn 回転量が上限を超えたエラーの文が単位まで読める形で出る() {
    let 文 = 運動種別の遷移エラー::回転量が上限を超えている {
        回転量: ラジアン::生成する(2.0),
        上限: 運動学的回転量の上限(),
    }
    .to_string();
    assert_eq!(文, "運動学的剛体の1刻みの回転量2ラジアンが上限1.5707964ラジアンを超えている");
}
