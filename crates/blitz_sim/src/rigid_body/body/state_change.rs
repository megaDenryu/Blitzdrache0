//! 剛体の状態の書き換え(判断7・判断18)。物理の刻みの中だけで呼ばれる局面であり、触れるのは配置・運動種別・実行状態・直近に休止から起きた理由の4つである。
//! 参照を読む側の口(`body.rs`)と分けているのは、書き換えの経路をこのファイル1つに閉じ、どの操作がどの不変条件を守るのかを1箇所で読めるようにするためである。
//! 注意: 休止させる操作は速度を零にし、起こす操作は静穏の連続細分数を零へ戻す。この対を崩すと、休止した島が速度を持ったまま止まるか、起きた直後の剛体が古い連続数で再び休止する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断7」「判断18」。

use super::super::body_error::剛体エラー;
use super::super::body_kind::運動種別;
use super::super::body_transition::剛体の状態の変更;
use super::super::execution_state::実行状態;
use super::super::motion_state::運動状態;
use super::super::placement::配置;
use super::super::quiet_substep_count::静穏の連続細分数;
use super::剛体;

impl 剛体 {
    // 運動種別の遷移や休止・再開・静穏の連続細分数の変更を不変条件を守って行う(判断7・18)。
    pub(crate) fn 状態を変更する(&mut self, 変更: 剛体の状態の変更) {
        match 変更 {
            剛体の状態の変更::動的に遷移する { 初速 } => {
                self.運動種別 = 運動種別::動的で始める(初速);
                self.実行状態 = 実行状態::起きている;
            }
            剛体の状態の変更::運動学的に遷移する { 次の配置, 導出速度 } => {
                self.運動種別 = 運動種別::運動学的で始める(導出速度);
                self.配置 = 次の配置;
                self.実行状態 = 実行状態::起きている;
            }
            剛体の状態の変更::静的に遷移する => {
                self.運動種別 = 運動種別::静的;
                self.実行状態 = 実行状態::起きている;
            }
            剛体の状態の変更::休止させる => {
                self.実行状態 = 実行状態::休止している;
                self.直近に休止から起きた理由 = None;
                if let 運動種別::動的 {
                    運動状態: ref mut 速度,
                ..
                } = self.運動種別
                {
                    *速度 = 運動状態::静止();
                }
            }
            剛体の状態の変更::起こす { 理由 } => {
                if self.実行状態 == 実行状態::休止している {
                    self.直近に休止から起きた理由 = Some(理由);
                }
                self.実行状態 = 実行状態::起きている;
                self.静穏の連続細分数を零へ戻す();
            }
            剛体の状態の変更::静穏の連続細分数を進める => {
                if let 運動種別::動的 {
                    静穏の連続細分数: ref mut 数,
                    ..
                } = self.運動種別
                {
                    *数 = 数.一つ進める();
                }
            }
            剛体の状態の変更::静穏の連続細分数を零にする => self.静穏の連続細分数を零へ戻す(),
        }
    }

    // 物理の細分が確定した配置と再構成した速度を動的な剛体へ書き戻す。蓄積器と静穏の数はそのまま保つ。
    pub(crate) fn 配置と速度を書き換える(&mut self, 新しい配置: 配置, 速度: 運動状態) -> Result<(), 剛体エラー> {
        let 運動種別::動的 { 運動状態, .. } = &mut self.運動種別 else {
            return Err(剛体エラー::動的でない剛体の状態を物理が書き換えようとした { 識別子: self.識別子 });
        };
        *運動状態 = 速度;
        self.配置 = 新しい配置;
        Ok(())
    }

    fn 静穏の連続細分数を零へ戻す(&mut self) {
        if let 運動種別::動的 {
            静穏の連続細分数: ref mut 数,
            ..
        } = self.運動種別
        {
            *数 = 静穏の連続細分数::零();
        }
    }
}
