//! 質量特性: 質量・物体原点から見た重心・重心まわりの慣性(主慣性と主軸)の組(判断4)。衝突形状の属性ではなく剛体が別に持つ。
//! 生成が質量の正値と重心の有限性を検査し、逆質量を1度だけ導いて保持する。主慣性の検査は`主慣性と主軸`の生成が行う。
//! 箱・球・カプセルの解析式からの生成は`mass_properties_shapes`が持つ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断4」。

use blitz_math::{キログラム, ローカル, 変位, 逆キログラム};

use super::mass_properties_error::質量特性エラー;
use super::principal_inertia::主慣性と主軸;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 質量特性 {
    質量: キログラム,
    逆質量: 逆キログラム,
    物体原点から見た重心: 変位<ローカル>,
    主慣性と主軸: 主慣性と主軸,
}

impl 質量特性 {
    /// 質量0・負・非有限と、非有限の重心を型付きエラーで拒む。
    pub fn 生成する(
        質量: キログラム, 物体原点から見た重心: 変位<ローカル>, 主慣性と主軸: 主慣性と主軸
    ) -> Result<Self, 質量特性エラー> {
        if !(質量.値().is_finite() && 質量.値() > 0.0) {
            return Err(質量特性エラー::質量が正でない { 質量 });
        }
        if !物体原点から見た重心.長さ().値().is_finite() {
            return Err(質量特性エラー::重心が非有限);
        }
        Ok(Self {
            質量,
            逆質量: 質量.逆質量()?,
            物体原点から見た重心,
            主慣性と主軸,
        })
    }

    pub fn 質量(&self) -> キログラム {
        self.質量
    }

    pub fn 逆質量(&self) -> 逆キログラム {
        self.逆質量
    }

    pub fn 物体原点から見た重心(&self) -> 変位<ローカル> {
        self.物体原点から見た重心
    }

    pub fn 主慣性と主軸(&self) -> &主慣性と主軸 {
        &self.主慣性と主軸
    }
}
