//! 配置が衝突数学層と受け渡す位置の試験(判断3の2026-09-08の実装の細目の境界(c))。担当するのは、細かい位置が非零の配置で、
//! 衝突へ渡した中心から返った点を重心局所へ写し、二段へ戻した点が真の位置(倍精度で評価)での形の表面上にあることを固定することである。
//! 粗い位置だけを引く誤った実装ではこの往復が細かい位置ぶんずれるため、反証として細かい位置を引いた形も並べる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断3」の2026-09-08の実装の細目

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ローカル, ワールド, 二段の位置, 位置, 変位};

use super::orientation::姿勢;
use super::placement::配置;

fn 世界の位置(x: f32, y: f32, z: f32) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

fn 局所の変位(x: f32, y: f32, z: f32) -> 変位<ローカル> {
    変位::成分から生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

// 原点から20.5メートルの重心に、その座標の表現の刻み幅の0.3倍の細かい位置を持たせた配置。畳むと粗い位置に戻る大きさである。
fn 細かい位置が非零の配置() -> (配置, f64) {
    let 粗い = 世界の位置(20.5, 18.335756, 9.168);
    let 細かい = メートル::生成する(20.5).表現の刻み幅().値() * 0.3;
    let 重心 = 二段の位置::粗い位置と細かい位置から生成する(
        粗い,
        変位::成分から生成する(メートル::生成する(細かい), メートル::生成する(細かい), メートル::生成する(細かい)),
    )
    .unwrap();
    (配置::二段の位置と姿勢から生成する(重心, 姿勢::恒等()), f64::from(細かい))
}

/// 衝突数学層は畳んだ中心から形の表面の点 p = 畳んだ中心 + r̄ を返す。それを写した局所点を二段へ戻すと、真の重心 + r̄ に一致する。
#[test]
fn 衝突が返した点を局所へ写して戻すと真の位置での表面の点になる() {
    let (配置, 細かい) = 細かい位置が非零の配置();
    let 表面の局所点 = 局所の変位(0.5, -0.5, 0.5);
    let 衝突が返した点 = 配置.衝突へ渡す重心の位置().変位を足す(配置.腕(表面の局所点));
    let 局所点 = 配置.衝突が返した世界位置を重心局所へ写す(衝突が返した点);
    assert!((局所点 - 表面の局所点).長さ().値() < 1.0e-7, "{局所点:?}");
    let 戻した = 配置.局所点の世界位置(局所点).倍精度で評価した位置();
    let 真の重心 = 配置.重心の位置().倍精度で評価した位置();
    assert!((戻した.x().値() - (真の重心.x().値() + 0.5)).abs() < 1.0e-9);
    assert!((戻した.y().値() - (真の重心.y().値() - 0.5)).abs() < 1.0e-9);
    assert!((戻した.z().値() - (真の重心.z().値() + 0.5)).abs() < 1.0e-9);
    assert!((真の重心.x().値() - f64::from(20.5f32) - 細かい).abs() < 1.0e-12);
}

/// 反証: 畳んだ中心でなく真の二段の重心を引いて写すと、戻した点が細かい位置ぶん表面からずれる。
#[test]
fn 真の重心を引いて写す誤った形では戻した点が細かい位置ぶんずれる() {
    let (配置, 細かい) = 細かい位置が非零の配置();
    let 表面の局所点 = 局所の変位(0.5, -0.5, 0.5);
    let 衝突が返した点 = 配置.衝突へ渡す重心の位置().変位を足す(配置.腕(表面の局所点));
    let 誤った局所点 = 配置.世界位置を重心局所へ写す(衝突が返した点);
    let 戻した = 配置.局所点の世界位置(誤った局所点).倍精度で評価した位置();
    let 真の重心 = 配置.重心の位置().倍精度で評価した位置();
    let ずれ = (戻した.x().値() - (真の重心.x().値() + 0.5)).abs();
    assert!((ずれ - 細かい).abs() < 細かい * 1.0e-3, "ずれ={ずれ} 細かい={細かい}");
}
