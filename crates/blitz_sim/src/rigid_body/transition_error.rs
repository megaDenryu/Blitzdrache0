//! 運動種別の遷移が拒む不正な操作と引数の型付きエラー(判断7)。
//! 1刻みの回転量がπ/2を超える配置の指定と、未登録の剛体への操作を型付きエラーで拒絶する。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断7: 運動種別の遷移は台帳の専用の操作であり、遷移後の状態は一意に決まる」

use thiserror::Error;

use blitz_math::ラジアン;

use super::body_id::剛体の識別子;

/// 運動種別の遷移が返すエラー。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 運動種別の遷移エラー {
    #[error("運動学的剛体の1刻みの回転量{回転量}が上限{上限}を超えている")]
    回転量が上限を超えている { 回転量: ラジアン, 上限: ラジアン },
    #[error("剛体(識別子: {識別子:?})が登録されていない")]
    剛体が登録されていない { 識別子: 剛体の識別子 },
}
