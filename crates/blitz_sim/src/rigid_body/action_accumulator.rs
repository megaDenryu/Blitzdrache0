//! 一刻みの作用の蓄積器: 動的剛体が1つの物理刻みの間だけ受け取る合力・合回転力・衝撃の和・回転衝撃の和(判断6)。
//! 6つの操作で積み、工程2の取り出し(`取り出す`)で所有ごと「一刻みの入力」と「一度だけ適用する衝撃」の2つへ分けて返す。取り出した後は空の蓄積器へ置き換わる。
//! 刻みの外で蓄積器に値が残っている状態は、所有者(運動種別の動的の枝)が取り出しと同時に空へ置き換えることで作れない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断6」。

use blitz_math::{ワールド, 力, 回転力, 回転衝撃, 変位, 衝撃};

use super::step_input::{一刻みの入力, 一度だけ適用する衝撃};

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 一刻みの作用の蓄積器 {
    合力: 力<ワールド>,
    合回転力: 回転力<ワールド>,
    衝撃の和: 衝撃<ワールド>,
    回転衝撃の和: 回転衝撃<ワールド>,
}

impl 一刻みの作用の蓄積器 {
    pub fn 空() -> Self {
        Self {
            合力: 力::零(),
            合回転力: 回転力::零(),
            衝撃の和: 衝撃::零(),
            回転衝撃の和: 回転衝撃::零(),
        }
    }

    pub fn 重心へ力を加える(&mut self, 力: 力<ワールド>) {
        self.合力 = self.合力 + 力;
    }

    pub fn 重心へ衝撃を加える(&mut self, 衝撃: 衝撃<ワールド>) {
        self.衝撃の和 = self.衝撃の和 + 衝撃;
    }

    pub fn 回転力を加える(&mut self, 回転力: 回転力<ワールド>) {
        self.合回転力 = self.合回転力 + 回転力;
    }

    pub fn 回転衝撃を加える(&mut self, 回転衝撃: 回転衝撃<ワールド>) {
        self.回転衝撃の和 = self.回転衝撃の和 + 回転衝撃;
    }

    /// 腕 r の点へ力を加える。F += 力、τ += r × 力。
    pub fn 点へ力を加える(&mut self, 腕: 変位<ワールド>, 力: 力<ワールド>) {
        self.重心へ力を加える(力);
        self.回転力を加える(腕.腕に掛かる力の回転力(力));
    }

    /// 腕 r の点へ衝撃を加える。P += 衝撃、L += r × 衝撃。
    pub fn 点へ衝撃を加える(&mut self, 腕: 変位<ワールド>, 衝撃: 衝撃<ワールド>) {
        self.重心へ衝撃を加える(衝撃);
        self.回転衝撃を加える(腕.腕に掛かる衝撃の回転衝撃(衝撃));
    }

    /// 工程2の取り出し。所有で受けて2つの型へ分け、力と回転力は細分すべてで積分する入力に、衝撃と回転衝撃は最初の細分が1度だけ適用する型になる。
    pub fn 取り出す(self) -> (一刻みの入力, 一度だけ適用する衝撃) {
        (
            一刻みの入力::生成する(self.合力, self.合回転力),
            一度だけ適用する衝撃::生成する(self.衝撃の和, self.回転衝撃の和),
        )
    }

    pub fn 空か(&self) -> bool {
        *self == Self::空()
    }
}
