//! 質量特性の検査(判断4): 質量0・負・非有限、主慣性の0・負・非有限、三角不等式の破れがそれぞれのエラーの枝になること・
//! 箱と球とカプセルの解析式が既知の値になり三角不等式を満たすことを固定する。

#![allow(clippy::unwrap_used)]

use blitz_math::{キログラム, キログラム平方メートル, クォータニオン, メートル, 変位};

use super::mass_properties::質量特性;
use super::mass_properties_error::質量特性エラー;
use super::principal_inertia::{主慣性, 主慣性と主軸};

fn 主慣性を作る(a: f32, b: f32, c: f32) -> 主慣性 {
    主慣性::生成する(
        キログラム平方メートル::生成する(a),
        キログラム平方メートル::生成する(b),
        キログラム平方メートル::生成する(c),
    )
}

fn 質量特性を作る(質量: f32, 主慣性: 主慣性) -> Result<質量特性, 質量特性エラー> {
    質量特性::生成する(
        キログラム::生成する(質量)?,
        変位::零(),
        主慣性と主軸::生成する(主慣性, クォータニオン::軸が一致する回転())?,
    )
}

#[test]
fn 質量の零と負と非有限を拒む() {
    assert!(matches!(
        質量特性を作る(0.0, 主慣性を作る(1.0, 2.0, 3.0)),
        Err(質量特性エラー::質量が正でない { .. })
    ));
    assert!(matches!(
        質量特性を作る(-1.0, 主慣性を作る(1.0, 2.0, 3.0)),
        Err(質量特性エラー::質量を作れない(_))
    ));
    assert!(matches!(
        質量特性を作る(f32::INFINITY, 主慣性を作る(1.0, 2.0, 3.0)),
        Err(質量特性エラー::質量を作れない(_))
    ));
}

#[test]
fn 主慣性の零と負と非有限は軸番号つきで拒み三角不等式の破れも拒む() {
    assert!(matches!(
        質量特性を作る(1.0, 主慣性を作る(1.0, 0.0, 3.0)),
        Err(質量特性エラー::主慣性が正でない { 軸番号: 2, .. })
    ));
    assert!(matches!(
        質量特性を作る(1.0, 主慣性を作る(1.0, 2.0, -3.0)),
        Err(質量特性エラー::主慣性が正でない { 軸番号: 3, .. })
    ));
    assert!(matches!(
        質量特性を作る(1.0, 主慣性を作る(f32::NAN, 2.0, 3.0)),
        Err(質量特性エラー::主慣性が正でない { 軸番号: 1, .. })
    ));
    assert!(matches!(
        質量特性を作る(1.0, 主慣性を作る(1.0, 1.0, 3.0)),
        Err(質量特性エラー::主慣性が三角不等式を破る { .. })
    ));
    // 等号(平面に分布した質量)は許す。
    assert!(質量特性を作る(1.0, 主慣性を作る(1.0, 2.0, 3.0)).is_ok());
    let 質量特性 = 質量特性を作る(4.0, 主慣性を作る(1.0, 2.0, 3.0)).unwrap();
    assert!((質量特性.逆質量().値() - 0.25).abs() < 1.0e-7);
    assert!((質量特性.主慣性と主軸().逆主慣性()[2].値() - 1.0 / 3.0).abs() < 1.0e-7);
}

#[test]
fn 箱と球とカプセルの解析式は既知の値になる() {
    let 箱 = 質量特性::一様な箱(
        キログラム::生成する(12.0).unwrap(),
        メートル::生成する(1.0),
        メートル::生成する(2.0),
        メートル::生成する(3.0),
    )
    .unwrap();
    let [x, y, z] = 箱.主慣性と主軸().主慣性().成分一覧().map(|値| 値.値());
    assert!(
        (x - 13.0).abs() < 1.0e-5 && (y - 10.0).abs() < 1.0e-5 && (z - 5.0).abs() < 1.0e-5,
        "{x} {y} {z}"
    );
    let 球 = 質量特性::一様な球(キログラム::生成する(5.0).unwrap(), メートル::生成する(2.0)).unwrap();
    assert!((球.主慣性と主軸().主慣性().第一.値() - 8.0).abs() < 1.0e-5);
    // 円柱の高さが0のカプセルは球に一致する。
    let カプセル = 質量特性::一様なカプセル(キログラム::生成する(5.0).unwrap(), メートル::生成する(2.0), メートル::生成する(0.0)).unwrap();
    assert!((カプセル.主慣性と主軸().主慣性().第二.値() - 8.0).abs() < 1.0e-4);
    let 長いカプセル = 質量特性::一様なカプセル(キログラム::生成する(1.0).unwrap(), メートル::生成する(0.1), メートル::生成する(1.0)).unwrap();
    let 主慣性 = 長いカプセル.主慣性と主軸().主慣性();
    assert!(主慣性.第一.値() > 主慣性.第二.値(), "軸に垂直な慣性が軸まわりより大きい: {主慣性:?}");
}
