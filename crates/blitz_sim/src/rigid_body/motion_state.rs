//! 運動状態: 剛体の並進速度と角速度の組。動的剛体では速度の再構成(判断9)の結果を保持する永続状態であり、運動学的剛体では外から与えた配置の差から導いた速度である。
//! 静的剛体はこの型を持たない(判断2)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断2」「判断9」。

use blitz_math::{ワールド, 角速度, 速度};

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 運動状態 {
    並進速度: 速度<ワールド>,
    角速度: 角速度<ワールド>,
}

impl 運動状態 {
    pub fn 生成する(並進速度: 速度<ワールド>, 角速度: 角速度<ワールド>) -> Self {
        Self { 並進速度, 角速度 }
    }

    /// 動いていない運動状態。
    pub fn 静止() -> Self {
        Self::生成する(速度::零(), 角速度::零())
    }

    pub fn 並進速度(&self) -> 速度<ワールド> {
        self.並進速度
    }

    pub fn 角速度(&self) -> 角速度<ワールド> {
        self.角速度
    }
}
