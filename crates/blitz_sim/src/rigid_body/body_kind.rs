//! 運動種別: 剛体の運動を誰が決めるかの区別(判断2)。静的・運動学的・動的の3枝であり、枝ごとに持つ状態が違う。
//! 静的は速度を持たず、運動学的は外から与えた配置の差から導いた速度を持ち、動的は速度と一刻みの作用の蓄積器と静穏の連続細分数を持つ。
//! 静的を「質量∞の動的」、運動学的を「毎刻み瞬間移動する動的」という特殊値で表さない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断2」。

use super::action_accumulator::一刻みの作用の蓄積器;
use super::motion_state::運動状態;
use super::quiet_substep_count::静穏の連続細分数;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 運動種別 {
    静的,
    運動学的 {
        運動状態: 運動状態,
    },
    動的 {
        運動状態: 運動状態,
        作用の蓄積器: 一刻みの作用の蓄積器,
        静穏の連続細分数: 静穏の連続細分数,
    },
}

impl 運動種別 {
    /// 初速を持つ動的な剛体。蓄積器は空、静穏の数は0(起きた状態)から始める。
    pub fn 動的で始める(初速: 運動状態) -> Self {
        Self::動的 {
            運動状態: 初速,
            作用の蓄積器: 一刻みの作用の蓄積器::空(),
            静穏の連続細分数: 静穏の連続細分数::零(),
        }
    }

    /// 外部が配置を決める剛体。速度は次の配置との差から導く(判断7。遷移の実装はIssue #40)。
    pub fn 運動学的で始める(運動状態: 運動状態) -> Self {
        Self::運動学的 { 運動状態 }
    }

    /// 動的または運動学的の速度。静的には無く、剛体の型がその無しを型付きエラーへ写す(消費側へ`Option`を運ばない)。
    pub fn 速度(&self) -> Option<運動状態> {
        match self {
            Self::静的 => None,
            Self::運動学的 { 運動状態 } | Self::動的 { 運動状態, .. } => Some(*運動状態),
        }
    }
}
