//! 運動種別: 剛体の運動を誰が決めるかの区別(判断2)。静的・運動学的・動的の3枝であり、枝ごとに持つ状態が違う。
//! 静的は速度を持たず、運動学的は外から与えた配置の差から導いた速度を持ち、動的は速度と一刻みの作用の蓄積器と静穏が続いた細分の本数を持つ。
//! 静的を「質量∞の動的」、運動学的を「毎刻み瞬間移動する動的」という特殊値で表さない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断2」。

use super::action_accumulator::一刻みの作用の蓄積器;
use super::motion_state::運動状態;
use super::quiet_substep_run::静穏が続いた細分の本数;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 運動種別 {
    静的,
    運動学的 {
        運動状態: 運動状態,
    },
    動的 {
        運動状態: 運動状態,
        作用の蓄積器: 一刻みの作用の蓄積器,
        静穏が続いた細分の本数: 静穏が続いた細分の本数,
    },
}

impl 運動種別 {
    /// 初速を持つ動的な剛体。蓄積器は空、静穏が続いた細分の本数は0本(起きた状態)から始める。
    pub fn 動的で始める(初速: 運動状態) -> Self {
        Self::動的 {
            運動状態: 初速,
            作用の蓄積器: 一刻みの作用の蓄積器::空(),
            静穏が続いた細分の本数: 静穏が続いた細分の本数::零(),
        }
    }

    /// 外部が配置を決める剛体。速度は次の配置との差から導く(判断7。遷移の実装はIssue #40)。
    pub fn 運動学的で始める(運動状態: 運動状態) -> Self {
        Self::運動学的 { 運動状態 }
    }

    /// 接触した相手が休止していたらその相手を起こす動きを、この運動種別が持つか(判断18の再開の条件「新しい接触」)。
    /// 動的と、速度が零でない運動学的だけが持つ。静的を除くのは、床の上で休止した剛体が床との接触点集合を細分ごとに作り直すたびに
    /// 起きてしまい、休止が1細分も続かないためである。
    pub fn 休止した相手を起こす動きを持つか(&self) -> bool {
        match self {
            Self::静的 => false,
            Self::運動学的 { 運動状態: 速度 } => *速度 != 運動状態::静止(),
            Self::動的 { .. } => true,
        }
    }

    /// 動的または運動学的の速度。静的には無く、剛体の型がその無しを型付きエラーへ写す(消費側へ`Option`を運ばない)。
    pub fn 速度(&self) -> Option<運動状態> {
        match self {
            Self::静的 => None,
            Self::運動学的 { 運動状態 } | Self::動的 { 運動状態, .. } => Some(*運動状態),
        }
    }
}
