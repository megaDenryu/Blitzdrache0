//! 作用の蓄積器の検査(判断6): 任意点への力と衝撃が腕の外積で回転力と回転衝撃になること・取り出しで2つの型へ分かれ蓄積器が空へ戻ること・
//! 一度だけ適用する衝撃が速度と角速度を w P と I⁻¹ L だけ変えることを固定する。

#![allow(clippy::unwrap_used)]

use blitz_math::{キログラム, ニュートン, ニュートン秒, メートル, ワールド, 位置, 力, 変位, 衝撃};

use super::action_accumulator::一刻みの作用の蓄積器;
use super::action_point::作用点;
use super::mass_properties::質量特性;
use super::motion_state::運動状態;
use super::orientation::姿勢;
use super::placement::配置;

fn 原点の配置() -> 配置 {
    配置::生成する(
        位置::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0)),
        姿勢::恒等(),
    )
}

fn y向きの力(大きさ: f32) -> 力<ワールド> {
    力::成分から生成する(ニュートン::生成する(0.0), ニュートン::生成する(大きさ), ニュートン::生成する(0.0))
}

#[test]
fn 重心から離れた点への力は回転力を生み重心への力は生まない() {
    let 配置 = 原点の配置();
    let mut 蓄積器 = 一刻みの作用の蓄積器::空();
    let 世界の点 = 作用点::世界位置(位置::生成する(
        メートル::生成する(2.0),
        メートル::生成する(0.0),
        メートル::生成する(0.0),
    ));
    蓄積器.点へ力を加える(世界の点.腕(&配置), y向きの力(3.0));
    蓄積器.重心へ力を加える(y向きの力(1.0));
    let (入力, _) = 蓄積器.取り出す();
    assert_eq!(入力.合力().y().値(), 4.0);
    assert_eq!(入力.合回転力().z().値(), 6.0);
    let 局所の点 = 作用点::重心局所の点(変位::成分から生成する(
        メートル::生成する(0.0),
        メートル::生成する(1.0),
        メートル::生成する(0.0),
    ));
    let mut 蓄積器 = 一刻みの作用の蓄積器::空();
    蓄積器.点へ衝撃を加える(
        局所の点.腕(&配置),
        衝撃::成分から生成する(ニュートン秒::生成する(0.0), ニュートン秒::生成する(0.0), ニュートン秒::生成する(5.0)),
    );
    assert!(!蓄積器.空か());
    let (_, 一度だけ) = 蓄積器.取り出す();
    let 質量特性 = 質量特性::一様な球(キログラム::生成する(2.0).unwrap(), メートル::生成する(1.0)).unwrap();
    let 逆慣性 = 姿勢::恒等().回転().逆慣性テンソルを回す(質量特性.主慣性と主軸().局所の逆慣性テンソル());
    let 速度 = 一度だけ.運動状態へ適用する(運動状態::静止(), 質量特性.逆質量(), &逆慣性);
    assert!((速度.並進速度().z().値() - 2.5).abs() < 1.0e-6, "{速度:?}");
    // 腕(0,1,0) × 衝撃(0,0,5) = (5,0,0)、球の慣性は 0.4×2×1 = 0.8 なので角速度は 6.25 になる。
    assert!((速度.角速度().x().値() - 6.25).abs() < 1.0e-5, "{速度:?}");
}
