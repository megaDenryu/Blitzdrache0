//! 配置: 剛体の重心の世界位置と姿勢の組(判断3)。動的剛体の物理位置の正本は重心である。
//! 重心の世界位置は二段の位置(粗い位置と細かい位置の和)で持ち、微小な補正が単精度の表現の刻み幅に負けて消えることを防ぐ。
//! 局所の点をワールドへ写す式 p = x + R(q) r̄ と腕 r = p − x はここが持ち、p は二段の位置のまま返す。
//! 和を単精度へ畳むのは、描画の変換の生成(`物体原点の世界位置`)の境界だけである。衝突数学層へ渡す形は畳まず、
//! `contact/query_origin.rs` の衝突の問い合わせの基準原点からの差として組む(判断3)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断3」「記法」。

use blitz_math::{ローカル, ワールド, 二段の位置, 位置, 回転ベクトル, 変位};

use super::orientation::姿勢;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 配置 {
    重心の位置: 二段の位置<ワールド>,
    姿勢: 姿勢,
}

impl 配置 {
    /// 単精度の世界位置(細かい位置は零)と姿勢から生成する。
    pub fn 生成する(重心の位置: 位置<ワールド>, 姿勢: 姿勢) -> Self {
        Self::二段の位置と姿勢から生成する(二段の位置::位置から生成する(重心の位置), 姿勢)
    }

    pub fn 二段の位置と姿勢から生成する(重心の位置: 二段の位置<ワールド>, 姿勢: 姿勢) -> Self {
        Self { 重心の位置, 姿勢 }
    }

    pub fn 重心の位置(&self) -> 二段の位置<ワールド> {
        self.重心の位置
    }

    pub fn 姿勢(&self) -> &姿勢 {
        &self.姿勢
    }

    /// 重心局所座標の点 r̄ の世界位置 p = x + R(q) r̄。二段の位置のまま返し、細かい位置は繰り上げ済みである。
    pub fn 局所点の世界位置(&self, 局所点: 変位<ローカル>) -> 二段の位置<ワールド> {
        self.重心の位置.変位を足す(self.腕(局所点))
    }

    /// 重心局所座標の点 r̄ の腕 r = R(q) r̄(重心から見たワールドの変位)。
    pub fn 腕(&self, 局所点: 変位<ローカル>) -> 変位<ワールド> {
        self.姿勢.回転().変位を回す(局所点)
    }

    /// 世界位置の点の腕 r = p − x。二段の重心から測る。
    pub fn 世界位置の腕(&self, 世界位置: 位置<ワールド>) -> 変位<ワールド> {
        世界位置 - self.重心の位置
    }

    /// 世界位置の点の重心局所座標 r̄ = R(q)ᵀ (p − x)。二段の重心から測る。
    pub fn 世界位置を重心局所へ写す(&self, 世界位置: 位置<ワールド>) -> 変位<ローカル> {
        self.姿勢.逆回転().変位を回す(self.世界位置の腕(世界位置))
    }

    /// 二段の世界位置の点の重心局所座標 r̄ = R(q)ᵀ (p − x)。2つの二段の位置の差で腕を取り、途中で単精度の世界座標へ潰さない。
    pub fn 二段の世界位置を重心局所へ写す(&self, 世界位置: 二段の位置<ワールド>) -> 変位<ローカル> {
        self.姿勢.逆回転().変位を回す(世界位置 - self.重心の位置)
    }

    /// 物体原点の世界位置 x − R(q) c̄ を単精度へ畳んだ値。描画とゲーム側が読む物体原点の変換はこの1箇所から作る。
    pub fn 物体原点の世界位置(&self, 物体原点から見た重心: 変位<ローカル>) -> 位置<ワールド> {
        self.重心の位置.変位を足す(-self.腕(物体原点から見た重心)).境界用に畳んだ位置()
    }

    /// 重心を変位だけ動かした配置。変位は細かい位置へ入り、繰り上げは二段の位置の型が行う。
    pub fn 並進で動かす(&self, 変位: 変位<ワールド>) -> Self {
        Self {
            重心の位置: self.重心の位置.変位を足す(変位),
            姿勢: self.姿勢,
        }
    }

    /// 姿勢をワールドの微小な回転で更新した配置。正規化は姿勢の型が行う。
    pub fn 微小回転で回す(&self, 回転: 回転ベクトル<ワールド>) -> Self {
        Self {
            重心の位置: self.重心の位置,
            姿勢: self.姿勢.微小回転で更新する(回転),
        }
    }
}
