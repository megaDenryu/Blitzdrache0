//! 休止から起きた理由: 判断18が定める6つの再開の条件を、起きた剛体の側へ記録するために型で持つ。
//! これはその剛体に直接起きた出来事ではなく、その剛体を含む島を再開させた契機である。休止と再開の単位が島であるため、
//! 島の1体への衝撃で島が起きたなら、島の全部の剛体が `作用の投入` を記録する。
//! 剛体の側に置くのは、起こす操作が剛体の実行状態を書き換える操作であり、どの契機で起きたかがその剛体の状態の一部だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断18: 休止は島の単位で行い、物理の結果を変えない最適化として再開の条件を型で持つ」。

/// 休止していた島を再開させた契機(判断18の再開の条件6つ)。島の全部の剛体が同じ値を記録する。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 休止から起きた理由 {
    /// 島の中の動的剛体へ力・回転力・衝撃・回転衝撃が加えられた。
    作用の投入,
    /// 島の中の剛体と、起きている動的剛体または速度が零でない運動学的剛体との接触点集合が生成された。
    新しい接触,
    /// 関節や目標拘束などの拘束が追加または除去された。
    拘束の着脱,
    /// 島の中の剛体の運動種別が変更された。
    運動種別の遷移,
    /// 剛体の生成や破棄を含む構造変更が行われた。
    構造変更,
    /// 島の剛体が触れうる区域の読込が完了した。
    区域の読込の完了,
}
