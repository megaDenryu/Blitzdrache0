//! 剛体の台帳の検査(判断2・判断6・判断23): 登録の順に識別子が発行されること・静的な剛体から速度を読めず作用も加えられないこと・
//! 運動学的な剛体へ作用を加えられないこと・動的な剛体の作用が取り出しで空へ戻ることを固定する。

#![allow(clippy::unwrap_used)]

use blitz_math::{キログラム, ニュートン, メートル, ワールド, 位置, 力};

use super::body_error::剛体エラー;
use super::body_kind::運動種別;
use super::ledger::剛体の台帳;
use super::mass_properties::質量特性;
use super::motion_state::運動状態;
use super::orientation::姿勢;
use super::placement::配置;

fn 配置と質量特性() -> (配置, 質量特性) {
    (
        配置::生成する(
            位置::生成する(メートル::生成する(0.0), メートル::生成する(1.0), メートル::生成する(0.0)),
            姿勢::恒等(),
        ),
        質量特性::一様な球(キログラム::生成する(1.0).unwrap(), メートル::生成する(0.5)).unwrap(),
    )
}

fn 上向きの力() -> 力<ワールド> {
    力::成分から生成する(ニュートン::生成する(0.0), ニュートン::生成する(2.0), ニュートン::生成する(0.0))
}

#[test]
fn 登録の順に識別子が発行され静的な剛体は速度も作用も持てない() {
    let (配置, 質量特性) = 配置と質量特性();
    let mut 台帳 = 剛体の台帳::空();
    let 静的 = 台帳.登録する(配置, 質量特性, 運動種別::静的).unwrap();
    let 運動学的 = 台帳.登録する(配置, 質量特性, 運動種別::運動学的で始める(運動状態::静止())).unwrap();
    let 動的 = 台帳.登録する(配置, 質量特性, 運動種別::動的で始める(運動状態::静止())).unwrap();
    assert!(静的 < 運動学的 && 運動学的 < 動的);
    assert_eq!(台帳.識別子一覧().collect::<Vec<_>>(), vec![静的, 運動学的, 動的]);
    assert_eq!(
        台帳.参照する(静的).unwrap().速度(),
        Err(剛体エラー::静的な剛体は速度を持たない { 識別子: 静的 })
    );
    assert_eq!(台帳.参照する(運動学的).unwrap().速度(), Ok(運動状態::静止()));
    assert_eq!(
        台帳.重心へ力を加える(静的, 上向きの力()),
        Err(剛体エラー::静的な剛体へ作用を加えようとした { 識別子: 静的 })
    );
    assert_eq!(
        台帳.重心へ力を加える(運動学的, 上向きの力()),
        Err(剛体エラー::運動学的な剛体へ作用を加えようとした { 識別子: 運動学的 })
    );
    assert_eq!(台帳.重心へ力を加える(動的, 上向きの力()), Ok(()));
    let (入力, _) = 台帳.作用を取り出す(動的).unwrap();
    assert_eq!(入力.合力().y().値(), 2.0);
    let (空の入力, _) = 台帳.作用を取り出す(動的).unwrap();
    assert_eq!(空の入力.合力().y().値(), 0.0, "取り出した後の蓄積器は空へ戻る");
}

#[test]
fn 登録されていない識別子は参照できない() {
    let (配置, 質量特性) = 配置と質量特性();
    let mut 台帳 = 剛体の台帳::空();
    let 識別子 = 台帳.登録する(配置, 質量特性, 運動種別::静的).unwrap();
    let 別の台帳 = 剛体の台帳::空();
    assert_eq!(別の台帳.参照する(識別子).map(|_| ()), Err(剛体エラー::剛体が登録されていない { 識別子 }));
}
