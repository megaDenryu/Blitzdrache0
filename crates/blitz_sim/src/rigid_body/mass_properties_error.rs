//! 質量特性の生成が拒む入力。質量・主慣性・三角不等式・重心のそれぞれが別の枝であり、検査は枝ごとに拒否を固定する(判断4)。

use blitz_math::{キログラム, キログラム平方メートル, 質量エラー};
use thiserror::Error;

#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 質量特性エラー {
    #[error("質量は正の有限値でなければならない(指定値: {質量:?})")]
    質量が正でない { 質量: キログラム },
    #[error("質量を作れない: {0}")]
    質量を作れない(#[from] 質量エラー),
    #[error("主慣性の第{軸番号}成分は正の有限値でなければならない(指定値: {値:?})")]
    主慣性が正でない { 軸番号: u8, 値: キログラム平方メートル },
    #[error("主慣性({第一:?}, {第二:?}, {第三:?})が三角不等式(どの2つの和も残りの1つ以上)を破る。物理的な質量分布に対応しない")]
    主慣性が三角不等式を破る {
        第一: キログラム平方メートル,
        第二: キログラム平方メートル,
        第三: キログラム平方メートル,
    },
    #[error("物体原点から見た重心の成分が有限値でない")]
    重心が非有限,
}
