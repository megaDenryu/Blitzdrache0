//! 運動種別の遷移の検査(判断7)。
//! 静的から動的への遷移で初速と起きた状態を持つこと、動的→静的→動的の往復で状態が初期化されることを検証する。

use blitz_math::{キログラム, メートル, メートル毎秒, ラジアン毎秒, ワールド, 位置, 秒, 角速度, 速度};

use super::body_kind::運動種別;
use super::execution_state::実行状態;
use super::ledger::剛体の台帳;
use super::mass_properties::質量特性;
use super::motion_state::運動状態;
use super::orientation::姿勢;
use super::placement::配置;

fn テスト用の位置() -> 位置<ワールド> {
    位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0))
}

fn 単体テスト用の質量特性() -> 質量特性 {
    let Ok(質量) = キログラム::生成する(1.0) else {
        panic!();
    };
    let Ok(特性) = 質量特性::一様な箱(質量, メートル::生成する(1.0), メートル::生成する(1.0), メートル::生成する(1.0))
    else {
        panic!();
    };
    特性
}

fn 単体テスト用の初速(並進y: f32, 角速度y: f32) -> 運動状態 {
    let 並進 =
        速度::<ワールド>::成分から生成する(メートル毎秒::生成する(0.0), メートル毎秒::生成する(並進y), メートル毎秒::生成する(0.0));
    let 回転 = 角速度::<ワールド>::成分から生成する(
        ラジアン毎秒::生成する(0.0),
        ラジアン毎秒::生成する(角速度y),
        ラジアン毎秒::生成する(0.0),
    );
    運動状態::生成する(並進, 回転)
}

#[test]
fn 静的から動的への遷移で起きた状態と指定の初速を持つ() {
    let mut 台帳 = 剛体の台帳::空();
    let 配置 = 配置::生成する(テスト用の位置(), 姿勢::恒等());
    let Ok(識別子) = 台帳.登録する(配置, 単体テスト用の質量特性(), 運動種別::静的) else {
        panic!();
    };
    let 初速 = 単体テスト用の初速(5.0, 1.0);
    台帳.遷移の予約().動的にする(識別子, 初速);
    assert_eq!(台帳.遷移の予約().件数(), 1);
    let 基本刻み = 秒::生成する(1.0 / 60.0);
    let mut 予約 = std::mem::take(台帳.遷移の予約());
    let Ok(遷移一覧) = 予約.反映する(台帳.剛体一覧_mut(), 基本刻み) else {
        panic!();
    };
    *台帳.遷移の予約() = 予約;
    assert_eq!(遷移一覧, vec![識別子]);
    assert_eq!(台帳.遷移の予約().件数(), 0);
    let Ok(剛体) = 台帳.参照する(識別子) else {
        panic!();
    };
    assert_eq!(剛体.実行状態(), 実行状態::起きている);
    let Ok(速度) = 剛体.速度() else {
        panic!();
    };
    assert_eq!(速度, 初速);
}

#[test]
fn 動的から静的を経て動的への遷移で状態が初期化される() {
    let mut 台帳 = 剛体の台帳::空();
    let 配置 = 配置::生成する(テスト用の位置(), 姿勢::恒等());
    let 初速1 = 単体テスト用の初速(2.0, 0.0);
    let Ok(識別子) = 台帳.登録する(配置, 単体テスト用の質量特性(), 運動種別::動的で始める(初速1)) else {
        panic!();
    };
    台帳.遷移の予約().静的にする(識別子);
    let 基本刻み = 秒::生成する(1.0 / 60.0);
    let mut 予約1 = std::mem::take(台帳.遷移の予約());
    let Ok(_) = 予約1.反映する(台帳.剛体一覧_mut(), 基本刻み) else {
        panic!();
    };
    *台帳.遷移の予約() = 予約1;
    let Ok(剛体_静的) = 台帳.参照する(識別子) else {
        panic!();
    };
    assert_eq!(*剛体_静的.運動種別(), 運動種別::静的);
    let 初速2 = 単体テスト用の初速(0.0, 3.0);
    台帳.遷移の予約().動的にする(識別子, 初速2);
    let mut 予約2 = std::mem::take(台帳.遷移の予約());
    let Ok(_) = 予約2.反映する(台帳.剛体一覧_mut(), 基本刻み) else {
        panic!();
    };
    *台帳.遷移の予約() = 予約2;
    let Ok(剛体_動的) = 台帳.参照する(識別子) else {
        panic!();
    };
    assert_eq!(剛体_動的.実行状態(), 実行状態::起きている);
    let Ok(速度) = 剛体_動的.速度() else {
        panic!();
    };
    assert_eq!(速度, 初速2);
}
