//! 剛体への作用の受け付けと取り出し(判断6)。触れるのは運動種別の動的の枝が持つ蓄積器と、腕を求めるための配置だけである。
//! 静的と運動学的の剛体へ作用を投入する操作は型付きエラーを返す。任意点への作用は作用点の型が腕を求め、蓄積器が回転力と回転衝撃へ写す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断6」。

use blitz_math::{ワールド, 力, 回転力, 回転衝撃, 衝撃};

use super::action_accumulator::一刻みの作用の蓄積器;
use super::action_point::作用点;
use super::body::剛体;
use super::body_error::剛体エラー;
use super::body_kind::運動種別;
use super::step_input::{一刻みの入力, 一度だけ適用する衝撃};

impl 剛体 {
    fn 蓄積器を借りる(&mut self) -> Result<&mut 一刻みの作用の蓄積器, 剛体エラー> {
        let 識別子 = self.識別子();
        match self.運動種別を書き換える() {
            運動種別::動的 { 作用の蓄積器, .. } => Ok(作用の蓄積器),
            運動種別::運動学的 { .. } => Err(剛体エラー::運動学的な剛体へ作用を加えようとした { 識別子 }),
            運動種別::静的 => Err(剛体エラー::静的な剛体へ作用を加えようとした { 識別子 }),
        }
    }

    pub fn 重心へ力を加える(&mut self, 力: 力<ワールド>) -> Result<(), 剛体エラー> {
        self.蓄積器を借りる().map(|蓄積器| 蓄積器.重心へ力を加える(力))
    }

    pub fn 重心へ衝撃を加える(&mut self, 衝撃: 衝撃<ワールド>) -> Result<(), 剛体エラー> {
        self.蓄積器を借りる().map(|蓄積器| 蓄積器.重心へ衝撃を加える(衝撃))
    }

    pub fn 回転力を加える(&mut self, 回転力: 回転力<ワールド>) -> Result<(), 剛体エラー> {
        self.蓄積器を借りる().map(|蓄積器| 蓄積器.回転力を加える(回転力))
    }

    pub fn 回転衝撃を加える(&mut self, 回転衝撃: 回転衝撃<ワールド>) -> Result<(), 剛体エラー> {
        self.蓄積器を借りる().map(|蓄積器| 蓄積器.回転衝撃を加える(回転衝撃))
    }

    pub fn 点へ力を加える(&mut self, 作用点: 作用点, 力: 力<ワールド>) -> Result<(), 剛体エラー> {
        let 腕 = 作用点.腕(self.配置());
        self.蓄積器を借りる().map(|蓄積器| 蓄積器.点へ力を加える(腕, 力))
    }

    pub fn 点へ衝撃を加える(&mut self, 作用点: 作用点, 衝撃: 衝撃<ワールド>) -> Result<(), 剛体エラー> {
        let 腕 = 作用点.腕(self.配置());
        self.蓄積器を借りる().map(|蓄積器| 蓄積器.点へ衝撃を加える(腕, 衝撃))
    }

    /// 工程2の取り出し。蓄積器を所有で取り出して空へ置き換え、一刻みの入力と一度だけ適用する衝撃に分けて返す。動的でない剛体は型付きエラーになる。
    pub(crate) fn 作用を取り出す(&mut self) -> Result<(一刻みの入力, 一度だけ適用する衝撃), 剛体エラー> {
        let 蓄積器 = self.蓄積器を借りる()?;
        Ok(std::mem::replace(蓄積器, 一刻みの作用の蓄積器::空()).取り出す())
    }
}
