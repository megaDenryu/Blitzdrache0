//! 蓄積器から取り出した作用の2つの型(判断6)。一刻みの入力(力と回転力)はn本の細分すべてで h ずつ積分され、n本の合計で H·F の運動量の変化になる。
//! 一度だけ適用する衝撃は最初の細分の予測の前に1回だけ速度へ足され、所有で消費されるため2本目以降の細分へ渡せない(n回加えるとn倍になる)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断6」「判断19」。

use blitz_math::{ワールド, 力, 回転力, 回転衝撃, 衝撃, 角速度, 逆キログラム, 逆慣性テンソル, 速度};

use super::motion_state::運動状態;

/// 力と回転力。細分ごとの予測が刻み幅を掛けて速度と角速度へ積分する。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 一刻みの入力 {
    合力: 力<ワールド>,
    合回転力: 回転力<ワールド>,
}

impl 一刻みの入力 {
    pub fn 生成する(合力: 力<ワールド>, 合回転力: 回転力<ワールド>) -> Self {
        Self { 合力, 合回転力 }
    }

    /// 作用の無い刻み。
    pub fn 無し() -> Self {
        Self::生成する(力::零(), 回転力::零())
    }

    pub fn 合力(&self) -> 力<ワールド> {
        self.合力
    }

    pub fn 合回転力(&self) -> 回転力<ワールド> {
        self.合回転力
    }
}

/// 衝撃と回転衝撃。最初の細分だけが所有で消費する。
#[derive(Debug, Clone, Copy, PartialEq)]
#[must_use = "一度だけ適用する衝撃は最初の細分が消費しなければ失われる"]
pub struct 一度だけ適用する衝撃 {
    衝撃の和: 衝撃<ワールド>,
    回転衝撃の和: 回転衝撃<ワールド>,
}

impl 一度だけ適用する衝撃 {
    pub fn 生成する(衝撃の和: 衝撃<ワールド>, 回転衝撃の和: 回転衝撃<ワールド>) -> Self {
        Self {
            衝撃の和, 回転衝撃の和
        }
    }

    /// 速度と角速度へ v += w P、ω += I⁻¹ L を1度だけ足す。自分を消費するため2度目は呼べない。
    pub fn 運動状態へ適用する(
        self, 運動状態: 運動状態, 逆質量: 逆キログラム, ワールドの逆慣性: &逆慣性テンソル<ワールド>
    ) -> 運動状態 {
        let 並進速度: 速度<ワールド> = 運動状態.並進速度() + self.衝撃の和 * 逆質量;
        let 角速度: 角速度<ワールド> = 運動状態.角速度() + ワールドの逆慣性.回転衝撃を角速度へ写す(self.回転衝撃の和);
        運動状態::生成する(並進速度, 角速度)
    }
}
