//! 剛体の台帳: 剛体の登録と参照と作用の受け付けを公開する操作サービス(判断23)の最小形。
//! この作業が持つのは登録・参照・作用の6操作・物理の細分からの書き戻しであり、破棄・運動種別の遷移・材質・接触の履歴・島・休止・空間索引への登録はIssue #40が足す。
//! 識別子は登録の順に発行する番号であり、破棄が無いこの作業では一覧の添字と一致する。破棄を足す日にこの対応を空きの管理へ置き換える。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断23」。

use super::body::剛体;
use super::body_error::剛体エラー;
use super::body_id::剛体の識別子;
use super::body_kind::運動種別;
use super::mass_properties::質量特性;
use super::motion_state::運動状態;
use super::placement::配置;

#[derive(Debug, Clone, PartialEq)]
pub struct 剛体の台帳 {
    剛体一覧: Vec<剛体>,
}

impl 剛体の台帳 {
    pub fn 空() -> Self {
        Self { 剛体一覧: Vec::new() }
    }

    /// 剛体を登録し、発行した識別子を返す。生成された剛体は起きた状態で始める。
    pub fn 登録する(
        &mut self, 配置: 配置, 質量特性: 質量特性, 運動種別: 運動種別
    ) -> Result<剛体の識別子, 剛体エラー> {
        let 番号 = u32::try_from(self.剛体一覧.len()).map_err(|_| 剛体エラー::剛体の数が過大)?;
        let 識別子 = 剛体の識別子::生成する(番号);
        self.剛体一覧.push(剛体::生成する(識別子, 配置, 質量特性, 運動種別));
        Ok(識別子)
    }

    pub fn 参照する(&self, 識別子: 剛体の識別子) -> Result<&剛体, 剛体エラー> {
        self.剛体一覧.get(識別子.配列添字()).ok_or(剛体エラー::剛体が登録されていない { 識別子 })
    }

    // 台帳の内部と物理の細分だけが書き換えの口を持つ。ゲーム側には見せない。
    pub(crate) fn 書き換える(&mut self, 識別子: 剛体の識別子) -> Result<&mut 剛体, 剛体エラー> {
        self.剛体一覧
            .get_mut(識別子.配列添字())
            .ok_or(剛体エラー::剛体が登録されていない { 識別子 })
    }

    // 物理の細分が確定した配置と再構成した速度を動的な剛体へ書き戻す。
    pub(crate) fn 配置と速度を書き換える(
        &mut self, 識別子: 剛体の識別子, 配置: 配置, 速度: 運動状態
    ) -> Result<(), 剛体エラー> {
        self.書き換える(識別子)?.配置と速度を書き換える(配置, 速度)
    }

    pub fn 剛体一覧(&self) -> &[剛体] {
        &self.剛体一覧
    }

    /// 登録の順に並んだ識別子。物理の細分が剛体を回す順であり、島の順序(判断17)もこの昇順を基準にする。
    pub fn 識別子一覧(&self) -> impl Iterator<Item = 剛体の識別子> + '_ {
        self.剛体一覧.iter().map(剛体::識別子)
    }
}
