//! 台帳が公開する作用の6操作(判断6・判断23)。識別子で剛体を引いて剛体の受け付けへ委ねる。触れるのはその剛体の蓄積器だけである。
//! 休止中の剛体へ作用を投入すると島が再開する規則(判断18)はIssue #40が足す。

use blitz_math::{ワールド, 力, 回転力, 回転衝撃, 衝撃};

use super::action_point::作用点;
use super::body_error::剛体エラー;
use super::body_id::剛体の識別子;
use super::ledger::剛体の台帳;
use super::step_input::{一刻みの入力, 一度だけ適用する衝撃};

impl 剛体の台帳 {
    pub fn 重心へ力を加える(&mut self, 識別子: 剛体の識別子, 力: 力<ワールド>) -> Result<(), 剛体エラー> {
        self.書き換える(識別子)?.重心へ力を加える(力)
    }

    pub fn 重心へ衝撃を加える(&mut self, 識別子: 剛体の識別子, 衝撃: 衝撃<ワールド>) -> Result<(), 剛体エラー> {
        self.書き換える(識別子)?.重心へ衝撃を加える(衝撃)
    }

    pub fn 回転力を加える(&mut self, 識別子: 剛体の識別子, 回転力: 回転力<ワールド>) -> Result<(), 剛体エラー> {
        self.書き換える(識別子)?.回転力を加える(回転力)
    }

    pub fn 回転衝撃を加える(
        &mut self, 識別子: 剛体の識別子, 回転衝撃: 回転衝撃<ワールド>
    ) -> Result<(), 剛体エラー> {
        self.書き換える(識別子)?.回転衝撃を加える(回転衝撃)
    }

    pub fn 点へ力を加える(
        &mut self, 識別子: 剛体の識別子, 作用点: 作用点, 力: 力<ワールド>
    ) -> Result<(), 剛体エラー> {
        self.書き換える(識別子)?.点へ力を加える(作用点, 力)
    }

    pub fn 点へ衝撃を加える(
        &mut self, 識別子: 剛体の識別子, 作用点: 作用点, 衝撃: 衝撃<ワールド>
    ) -> Result<(), 剛体エラー> {
        self.書き換える(識別子)?.点へ衝撃を加える(作用点, 衝撃)
    }

    // 工程2の取り出し。物理刻みの開始で動的な剛体ごとに1回呼び、蓄積器を空へ戻す。
    pub(crate) fn 作用を取り出す(
        &mut self,
        識別子: 剛体の識別子,
    ) -> Result<(一刻みの入力, 一度だけ適用する衝撃), 剛体エラー> {
        self.書き換える(識別子)?.作用を取り出す()
    }
}
