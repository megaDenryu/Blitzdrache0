//! 静穏が続いた細分の本数: 動的剛体が連続して静穏である細分の本数(判断18)。島の全剛体でこの本数が閾値へ達すると島が休止する。
//! 閾値の正本は物理時間0.125秒であり、その時間を細分の刻み幅で数えた本数が閾値になる(導出は`contact_thresholds`が持つ)。
//! 秒を積まずに本数を数えるのは、単精度の秒を細分ごとに足すと丸めが積もり、閾値の境目が1本ずれるためである。
//! 実測では、細分数8で61本目、16で121本目に休止しており、正本の60本と120本から1本遅れていた。

#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 静穏が続いた細分の本数(u32);

impl 静穏が続いた細分の本数 {
    /// 起きた直後、または静穏でない細分を挟んだ直後の値。
    pub fn 零() -> Self {
        Self(0)
    }

    /// 数えた本数から作る。閾値の側もこの型で表すため、導出した本数をこの口から包む。
    pub fn 本数から生成する(本数: u32) -> Self {
        Self(本数)
    }

    pub fn 本数(&self) -> u32 {
        self.0
    }

    /// 静穏な細分を1本通過したときの値。
    /// 上限で止めるのは、休止した島を数え続けないため実際には到達しない一方、桁溢れで零へ戻ると休止が消えるためである。
    pub fn 一本増やす(&self) -> Self {
        Self(self.0.saturating_add(1))
    }

    /// 休止と判定する本数へ達したか。
    pub fn 閾値に達したか(&self, 閾値: 静穏が続いた細分の本数) -> bool {
        self.0 >= 閾値.0
    }
}
