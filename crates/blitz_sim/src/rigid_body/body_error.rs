//! 剛体と台帳の操作が拒む要求。静的と運動学的の剛体へ作用を加えること、静的な剛体から速度を読むこと、登録されていない識別子を指すことが枝である。

use thiserror::Error;

use super::body_id::剛体の識別子;

#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 剛体エラー {
    #[error("静的な剛体{識別子:?}へ作用を加えようとした(静的な剛体は物理計算中に配置が変わらない)")]
    静的な剛体へ作用を加えようとした { 識別子: 剛体の識別子 },
    #[error("運動学的な剛体{識別子:?}へ作用を加えようとした(運動学的な剛体は外部が配置を決める)")]
    運動学的な剛体へ作用を加えようとした { 識別子: 剛体の識別子 },
    #[error("静的な剛体{識別子:?}は速度を持たない")]
    静的な剛体は速度を持たない { 識別子: 剛体の識別子 },
    #[error("動的でない剛体{識別子:?}の配置と速度を物理が書き換えようとした")]
    動的でない剛体の状態を物理が書き換えようとした { 識別子: 剛体の識別子 },
    #[error("剛体{識別子:?}は台帳に登録されていない")]
    剛体が登録されていない { 識別子: 剛体の識別子 },
    #[error("登録できる剛体の数がu32の範囲を超えた")]
    剛体の数が過大,
}
