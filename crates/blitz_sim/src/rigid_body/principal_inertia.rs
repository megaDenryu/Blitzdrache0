//! 主慣性と主軸: 重心まわりの慣性を対角化したときの3つの正の固有値と、その固有ベクトルが張る座標系の回転(判断4)。
//! 生成が正値と三角不等式(どの2つの和も残りの1つ以上。等号は平面に分布した質量)を検査し、逆主慣性と局所の慣性テンソルと逆慣性テンソルを1度だけ導いて保持する。
//! 任意の対称3×3行列を対角化する仕事は制作時(Issue #19)に置き、実行時の型は対角化済みだけを受ける。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断4」。

use blitz_math::{
    キログラム平方メートル, クォータニオン, ローカル, 主軸, 慣性テンソル, 逆キログラム平方メートル, 逆慣性テンソル
};

use super::mass_properties_error::質量特性エラー;

/// 主慣性の3値。第一から第三の順は主軸の回転の第一軸から第三軸に対応する。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 主慣性 {
    pub 第一: キログラム平方メートル,
    pub 第二: キログラム平方メートル,
    pub 第三: キログラム平方メートル,
}

impl 主慣性 {
    pub fn 生成する(
        第一: キログラム平方メートル, 第二: キログラム平方メートル, 第三: キログラム平方メートル
    ) -> Self {
        Self { 第一, 第二, 第三 }
    }

    /// 正値と三角不等式を検査し、逆主慣性を導く。
    fn 検査して逆主慣性を導く(&self) -> Result<[逆キログラム平方メートル; 3], 質量特性エラー> {
        for (軸番号, 値) in [(1u8, self.第一), (2, self.第二), (3, self.第三)] {
            if !(値.値().is_finite() && 値.値() > 0.0) {
                return Err(質量特性エラー::主慣性が正でない { 軸番号, 値 });
            }
        }
        let [a, b, c] = self.成分一覧().map(|値| 値.値());
        if a + b < c || b + c < a || c + a < b {
            return Err(質量特性エラー::主慣性が三角不等式を破る {
                第一: self.第一,
                第二: self.第二,
                第三: self.第三,
            });
        }
        Ok([self.第一.逆慣性()?, self.第二.逆慣性()?, self.第三.逆慣性()?])
    }

    pub fn 成分一覧(&self) -> [キログラム平方メートル; 3] {
        [self.第一, self.第二, self.第三]
    }
}

/// 検査済みの主慣性と主軸の組。局所の慣性テンソルと逆慣性テンソルを保持し、ワールドの逆慣性は姿勢が変わるたびに使う場所で組む。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 主慣性と主軸 {
    主慣性: 主慣性,
    逆主慣性: [逆キログラム平方メートル; 3],
    主軸: クォータニオン<主軸, ローカル>,
    局所の慣性テンソル: 慣性テンソル<ローカル>,
    局所の逆慣性テンソル: 逆慣性テンソル<ローカル>,
}

impl 主慣性と主軸 {
    /// 正値と三角不等式の破れを型付きエラーで拒む。
    pub fn 生成する(主慣性: 主慣性, 主軸: クォータニオン<主軸, ローカル>) -> Result<Self, 質量特性エラー> {
        let 逆主慣性 = 主慣性.検査して逆主慣性を導く()?;
        Ok(Self {
            主慣性,
            逆主慣性,
            主軸,
            局所の慣性テンソル: 慣性テンソル::主軸と主慣性から生成する(&主軸, 主慣性.成分一覧()),
            局所の逆慣性テンソル: 逆慣性テンソル::主軸と逆主慣性から生成する(&主軸, 逆主慣性),
        })
    }

    pub fn 主慣性(&self) -> 主慣性 {
        self.主慣性
    }

    pub fn 逆主慣性(&self) -> [逆キログラム平方メートル; 3] {
        self.逆主慣性
    }

    pub fn 主軸(&self) -> &クォータニオン<主軸, ローカル> {
        &self.主軸
    }

    pub fn 局所の慣性テンソル(&self) -> &慣性テンソル<ローカル> {
        &self.局所の慣性テンソル
    }

    pub fn 局所の逆慣性テンソル(&self) -> &逆慣性テンソル<ローカル> {
        &self.局所の逆慣性テンソル
    }
}
