//! 姿勢: 剛体の重心局所座標からワールド座標への回転を表す単位四元数の型。生成が長さを検証し、演算の戻り値の生成が正規化を行う(判断3)。
//! 生の4成分を取り出す口は`境界用xyzw配列`の1つであり、GPUのバイト列化と描画の変換の生成だけが読む。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断3」、`_doc/計画/ユビキタス言語.md`「剛体の語彙」。

use blitz_math::{クォータニオン, ローカル, ワールド, 回転ベクトル};
use thiserror::Error;

// 生成が受け入れる、単位長からのずれの上限。積分と補正の戻り値は正規化済みであるため、この検査は外から与えた成分だけに掛かる。
const 単位長の許容差: f32 = 1.0e-4;

/// 剛体の姿勢。長さ1の四元数であることを不変条件に持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
#[repr(transparent)]
pub struct 姿勢(クォータニオン<ローカル, ワールド>);

impl 姿勢 {
    /// x・y・z・wの成分から生成する。非有限と、長さが1から`1e-4`以上ずれた値を型付きエラーで拒む(無言の正規化はしない)。
    pub fn 生成する(x: f32, y: f32, z: f32, w: f32) -> Result<Self, 姿勢エラー> {
        if ![x, y, z, w].iter().all(|成分| 成分.is_finite()) {
            return Err(姿勢エラー::非有限成分 { x, y, z, w });
        }
        let 長さ = (x * x + y * y + z * z + w * w).sqrt();
        if (長さ - 1.0).abs() > 単位長の許容差 {
            return Err(姿勢エラー::単位長でない { 長さ });
        }
        クォータニオン::生成する(x, y, z, w)
            .map(Self)
            .map_err(|_| 姿勢エラー::単位長でない { 長さ })
    }

    /// 重心局所座標がワールド座標と一致する姿勢。
    pub fn 恒等() -> Self {
        Self(クォータニオン::軸が一致する回転())
    }

    /// 検証済みの回転から生成する。回転の型は生成が正規化を保証しているため、この生成は失敗しない。
    pub fn 回転から生成する(回転: クォータニオン<ローカル, ワールド>) -> Self {
        Self(回転)
    }

    /// 重心局所からワールドへの回転。局所の変位・方向・角速度・逆慣性をワールドへ写すときにこれを読み、逆は`逆回転()`で写す。
    pub fn 回転(&self) -> クォータニオン<ローカル, ワールド> {
        self.0
    }

    /// ワールドから重心局所への回転。
    pub fn 逆回転(&self) -> クォータニオン<ワールド, ローカル> {
        self.0.逆回転()
    }

    /// ワールドの微小な回転で更新した姿勢。積分(θ = h ω)と拘束の補正(θ = I⁻¹ (r × Δλ n))がこれを読み、正規化は戻り値の生成が行う。
    pub fn 微小回転で更新する(&self, 回転: 回転ベクトル<ワールド>) -> Self {
        Self(self.0.微小回転で更新する(回転))
    }

    /// 前の姿勢からこの姿勢までの回転 q ⊗ q_前⁻¹ を微小な回転として読んだ回転ベクトル。速度の再構成が刻み幅で割って角速度にする(判断9)。
    pub fn 前の姿勢からの微小回転(&self, 前: &姿勢) -> 回転ベクトル<ワールド> {
        前.逆回転().続けて回す(&self.0).微小回転として回転ベクトルへ()
    }

    /// 相手の姿勢をこの剛体の重心局所座標で表した回転 q_自分⁻¹ ⊗ q_相手。ねじりの拘束が相対の回転ベクトルを自分の局所で読む(判断10)。
    pub fn 相手の姿勢を自分の局所で表す(&self, 相手: &姿勢) -> クォータニオン<ローカル, ローカル> {
        相手.0.続けて回す(&self.逆回転())
    }

    /// 単位長からのずれ。検査が正規化の維持を見るために読む。
    pub fn 長さの1からのずれ(&self) -> f32 {
        self.0.長さの1からのずれ()
    }

    /// 境界向けの唯一の生値出口。x・y・z・wの順であり、`生成する`の引数の順と対になる。
    pub fn 境界用xyzw配列(&self) -> [f32; 4] {
        self.0.境界用xyzw配列()
    }
}

/// 姿勢の生成が拒んだ入力。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 姿勢エラー {
    #[error("姿勢の成分が有限値でない(指定値: ({x}, {y}, {z}, {w}))")]
    非有限成分 { x: f32, y: f32, z: f32, w: f32 },
    #[error("姿勢の四元数の長さ{長さ}が1から{単位長の許容差}以上ずれている")]
    単位長でない { 長さ: f32 },
}
