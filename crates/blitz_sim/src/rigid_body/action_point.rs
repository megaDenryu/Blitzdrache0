//! 作用点: 任意点への力と衝撃を受け付けるときの、その点の指定(判断6)。世界位置と重心局所の点の2枝であり、腕の計算はこの型のメソッドである。
//! 呼び出し側(ゲーム側)は腕を計算しない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断6」。

use blitz_math::{ローカル, ワールド, 位置, 変位};

use super::placement::配置;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 作用点 {
    世界位置(位置<ワールド>),
    重心局所の点(変位<ローカル>),
}

impl 作用点 {
    /// この点の腕 r(重心から見たワールドの変位)。世界位置なら 世界位置 − x、局所の点なら R(q) r̄ である。
    pub fn 腕(&self, 配置: &配置) -> 変位<ワールド> {
        match self {
            Self::世界位置(世界位置) => 配置.世界位置の腕(*世界位置),
            Self::重心局所の点(局所点) => 配置.腕(*局所点),
        }
    }
}
