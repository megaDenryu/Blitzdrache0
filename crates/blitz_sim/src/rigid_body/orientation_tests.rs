//! 姿勢の検査(判断3): 長さが1から1e-4以上ずれた成分と非有限の成分を拒むこと・前の姿勢からの微小回転と相手の姿勢の局所表現が期待の回転になること・
//! 局所点の世界位置と腕と物体原点の復元が式どおりであることを固定する。正規化の維持そのものはblitz_mathの回転の検査が持つ。

#![allow(clippy::unwrap_used)]

use blitz_math::{クォータニオン, メートル, ラジアン, ローカル, ワールド, 位置, 回転ベクトル, 変位};

use super::orientation::{姿勢, 姿勢エラー};
use super::placement::配置;

fn z軸まわりの姿勢(角: f32) -> 姿勢 {
    let 回転 = 回転ベクトル::成分から生成する(ラジアン::生成する(0.0), ラジアン::生成する(0.0), ラジアン::生成する(角));
    姿勢::回転から生成する(クォータニオン::<ローカル, ワールド>::回転ベクトルから生成する(
        回転,
    ))
}

fn 変位を作る(x: f32, y: f32, z: f32) -> 変位<ローカル> {
    変位::成分から生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

#[test]
fn 単位長から離れた成分と非有限の成分を拒み単位長の成分を受け入れる() {
    assert!(姿勢::生成する(0.0, 0.0, 0.0, 1.0).is_ok());
    assert!(姿勢::生成する(0.0, 0.0, 0.0, 1.0 + 5.0e-5).is_ok());
    assert!(matches!(姿勢::生成する(0.0, 0.0, 0.0, 1.001), Err(姿勢エラー::単位長でない { .. })));
    assert!(matches!(姿勢::生成する(0.0, 0.0, 0.0, 0.0), Err(姿勢エラー::単位長でない { .. })));
    assert!(matches!(姿勢::生成する(f32::NAN, 0.0, 0.0, 1.0), Err(姿勢エラー::非有限成分 { .. })));
}

#[test]
fn 前の姿勢からの微小回転は回した角と一致し相手の姿勢の局所表現は相対の回転になる() {
    let 前 = z軸まわりの姿勢(0.3);
    let 今 = 前.微小回転で更新する(回転ベクトル::成分から生成する(
        ラジアン::生成する(0.0),
        ラジアン::生成する(0.0),
        ラジアン::生成する(1.0e-3),
    ));
    let 微小回転 = 今.前の姿勢からの微小回転(&前);
    assert!((微小回転.z().値() - 1.0e-3).abs() < 1.0e-7, "{微小回転:?}");
    let 相手 = z軸まわりの姿勢(0.8);
    let 相対 = 前.相手の姿勢を自分の局所で表す(&相手).対数写像で回転ベクトルへ();
    assert!((相対.z().値() - 0.5).abs() < 1.0e-6, "{相対:?}");
}

#[test]
fn 局所点の世界位置と腕と物体原点の復元は回転と平行移動の式どおりである() {
    let 重心 = 位置::生成する(メートル::生成する(1.0), メートル::生成する(2.0), メートル::生成する(3.0));
    let 配置 = 配置::生成する(重心, z軸まわりの姿勢(std::f32::consts::FRAC_PI_2));
    let 局所点 = 変位を作る(1.0, 0.0, 0.0);
    let 腕 = 配置.腕(局所点);
    assert!((腕.x().値()).abs() < 1.0e-6 && (腕.y().値() - 1.0).abs() < 1.0e-6, "{腕:?}");
    let 世界位置 = 配置.局所点の世界位置(局所点);
    assert!((世界位置.y().値() - 3.0).abs() < 1.0e-6, "{世界位置:?}");
    assert!((配置.世界位置の腕(世界位置) - 腕).長さ().値() < 1.0e-6);
    let 物体原点 = 配置.物体原点の世界位置(局所点);
    assert!(
        (物体原点.y().値() - 1.0).abs() < 1.0e-6 && (物体原点.x().値() - 1.0).abs() < 1.0e-6,
        "{物体原点:?}"
    );
    assert_eq!(配置.並進で動かす(配置.腕(局所点)).重心の位置(), 世界位置);
}
