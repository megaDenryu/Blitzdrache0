//! 運動種別の遷移の予約(判断7)。
//! 運動種別の変更は遷移の予約の待ち行列に積まれ、工程1(構造変更の反映)で順に反映される。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断7: 運動種別の遷移は台帳の専用の操作であり、遷移後の状態は一意に決まる」

use blitz_math::秒;

use super::body::剛体;
use super::body_id::剛体の識別子;
use super::body_transition::剛体の状態の変更;
use super::motion_state::運動状態;
use super::placement::配置;
use super::transition_error::運動種別の遷移エラー;

/// 1件の運動種別の変更予約。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 運動種別の遷移の予約項目 {
    動的にする { 識別子: 剛体の識別子, 初速: 運動状態 },
    運動学的にする { 識別子: 剛体の識別子, 次の配置: 配置 },
    静的にする { 識別子: 剛体の識別子 },
}

impl 運動種別の遷移の予約項目 {
    pub fn 識別子(&self) -> 剛体の識別子 {
        match *self {
            Self::動的にする { 識別子, .. } | Self::運動学的にする { 識別子, .. } | Self::静的にする { 識別子 } => {
                識別子
            }
        }
    }
}

/// 構造変更の待ち行列として運動種別の遷移予約を保持する型(判断7)。
#[derive(Debug, Clone, PartialEq, Default)]
pub struct 運動種別の遷移の予約 {
    待ち行列: Vec<運動種別の遷移の予約項目>,
}

impl 運動種別の遷移の予約 {
    pub fn 空() -> Self {
        Self { 待ち行列: Vec::new() }
    }

    pub fn 動的にする(&mut self, 識別子: 剛体の識別子, 初速: 運動状態) {
        self.待ち行列.push(運動種別の遷移の予約項目::動的にする { 識別子, 初速 });
    }

    pub fn 運動学的にする(&mut self, 識別子: 剛体の識別子, 次の配置: 配置) {
        self.待ち行列.push(運動種別の遷移の予約項目::運動学的にする { 識別子, 次の配置 });
    }

    pub fn 静的にする(&mut self, 識別子: 剛体の識別子) {
        self.待ち行列.push(運動種別の遷移の予約項目::静的にする { 識別子 });
    }

    pub fn 件数(&self) -> usize {
        self.待ち行列.len()
    }

    /// 工程1: 積まれた遷移の予約を順に反映し、遷移した剛体の識別子一覧(昇順・重複なし)を返す。
    pub fn 反映する(
        &mut self, 剛体一覧: &mut [剛体], 基本刻み: 秒
    ) -> Result<Vec<剛体の識別子>, 運動種別の遷移エラー> {
        let 予約一覧 = std::mem::take(&mut self.待ち行列);
        let mut 遷移した剛体一覧 = Vec::with_capacity(予約一覧.len());
        for 予約 in 予約一覧 {
            let id = 予約.識別子();
            let 剛体 = 剛体一覧
                .get_mut(id.配列添字())
                .ok_or(運動種別の遷移エラー::剛体が登録されていない { 識別子: id })?;
            match 予約 {
                運動種別の遷移の予約項目::動的にする { 初速, .. } => {
                    剛体.状態を変更する(剛体の状態の変更::動的に遷移する { 初速 });
                }
                運動種別の遷移の予約項目::運動学的にする { 次の配置, .. } => {
                    let 導出速度 = 剛体.配置().次の配置へ移る運動学的な速度を導く(&次の配置, 基本刻み)?;
                    剛体.状態を変更する(剛体の状態の変更::運動学的に遷移する { 次の配置, 導出速度 });
                }
                運動種別の遷移の予約項目::静的にする { .. } => {
                    剛体.状態を変更する(剛体の状態の変更::静的に遷移する);
                }
            }
            遷移した剛体一覧.push(id);
        }
        遷移した剛体一覧.sort_unstable();
        遷移した剛体一覧.dedup();
        Ok(遷移した剛体一覧)
    }
}
