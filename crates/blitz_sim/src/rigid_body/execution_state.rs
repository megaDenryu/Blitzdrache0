//! 実行状態: 剛体が起きているか休止しているか(判断2・判断18)。
//! 起きている枝が「直近に休止から起きた理由」を持つのは、その理由が起きているときにしか意味を持たないためである。
//! その値は剛体を含む島を再開させた契機であり、同じ島の剛体は同じ値を持つ(判断18)。
//! 剛体の独立したフィールドで持つと「休止している、かつ直近に起きた理由がある」という起こり得ない組み合わせが型の上で表現可能になる。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断2」「判断18」。

use super::wake_reason::休止から起きた理由;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 実行状態 {
    /// 予測・接触点集合の生成・反復・速度段階を回す状態。生成された直後の剛体は理由を持たない。
    起きている {
        直近に休止から起きた理由: Option<休止から起きた理由>
    },
    /// 予測から速度段階までを省き、速度と角速度を0にして配置を保つ状態。
    休止している,
}

impl 実行状態 {
    /// まだ一度も休止していない剛体の状態。
    pub fn 休止したことがなく起きている() -> Self {
        Self::起きている {
            直近に休止から起きた理由: None,
        }
    }

    pub fn 起きているか(&self) -> bool {
        matches!(self, Self::起きている { .. })
    }

    pub fn 休止しているか(&self) -> bool {
        matches!(self, Self::休止している)
    }

    /// この剛体を含む島を最後に再開させた契機(判断18)。休止中と、一度も休止していない剛体は持たない。
    pub fn 直近に休止から起きた理由(&self) -> Option<休止から起きた理由> {
        match self {
            Self::起きている {
                直近に休止から起きた理由
            } => *直近に休止から起きた理由,
            Self::休止している => None,
        }
    }
}
