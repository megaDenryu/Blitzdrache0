//! 一様な密度の原始形状(箱・球・カプセル)の解析式から質量特性を作る関連関数。Issue #19が質量特性を焼き込む日までの初版の生成経路である(判断4)。
//! どの形も物体原点を重心に置き、主軸は局所座標の軸そのもの(恒等)である。カプセルの軸は局所座標の第二軸(y)である。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断4」。

use blitz_math::{キログラム, キログラム平方メートル, クォータニオン, メートル, 変位};

use super::mass_properties::質量特性;
use super::mass_properties_error::質量特性エラー;
use super::principal_inertia::{主慣性, 主慣性と主軸};

impl 質量特性 {
    /// 一辺の長さが(横, 縦, 奥)の一様な箱。J_x = m(縦² + 奥²) ÷ 12 の形である。
    pub fn 一様な箱(質量: キログラム, 横: メートル, 縦: メートル, 奥: メートル) -> Result<Self, 質量特性エラー> {
        let (m, x, y, z) = (質量.値(), 横.値(), 縦.値(), 奥.値());
        Self::重心に原点を置いて生成する(
            質量,
            主慣性::生成する(
                キログラム平方メートル::生成する(m * (y * y + z * z) / 12.0),
                キログラム平方メートル::生成する(m * (z * z + x * x) / 12.0),
                キログラム平方メートル::生成する(m * (x * x + y * y) / 12.0),
            ),
        )
    }

    /// 一様な球。J = 2 m r² ÷ 5 である。
    pub fn 一様な球(質量: キログラム, 半径: メートル) -> Result<Self, 質量特性エラー> {
        let 慣性 = キログラム平方メートル::生成する(0.4 * 質量.値() * 半径.値() * 半径.値());
        Self::重心に原点を置いて生成する(質量, 主慣性::生成する(慣性, 慣性, 慣性))
    }

    /// 軸が第二軸の一様なカプセル(半径 r の円柱の両端に半球)。円柱と2つの半球へ質量を体積比で配り、半球の重心のずれを平行軸の定理で足す。
    pub fn 一様なカプセル(
        質量: キログラム, 半径: メートル, 円柱の高さ: メートル
    ) -> Result<Self, 質量特性エラー> {
        let (m, r, h) = (質量.値(), 半径.値(), 円柱の高さ.値());
        let 円柱の質量 = m * h / (h + 4.0 * r / 3.0);
        let 半球2つの質量 = m - 円柱の質量;
        let 軸まわり = 円柱の質量 * r * r / 2.0 + 半球2つの質量 * 0.4 * r * r;
        let 軸に垂直 = 円柱の質量 * (r * r / 4.0 + h * h / 12.0) + 半球2つの質量 * (0.4 * r * r + h * h / 4.0 + 3.0 * h * r / 8.0);
        Self::重心に原点を置いて生成する(
            質量,
            主慣性::生成する(
                キログラム平方メートル::生成する(軸に垂直),
                キログラム平方メートル::生成する(軸まわり),
                キログラム平方メートル::生成する(軸に垂直),
            ),
        )
    }

    fn 重心に原点を置いて生成する(質量: キログラム, 主慣性: 主慣性) -> Result<Self, 質量特性エラー> {
        Self::生成する(質量, 変位::零(), 主慣性と主軸::生成する(主慣性, クォータニオン::軸が一致する回転())?)
    }
}
