//! 判断8の検査の観測値を印字する。`cargo test -p blitz_sim prediction_observation -- --nocapture`で走らせると、
//! `_doc/計測/剛体の姿勢自由度_2026-09-02.md`の表と同じ値が出る(自由回転の角運動量の比・散逸の減少量・中間軸の反転の細分・陽的の発散の細分)。
//! 合否は`prediction_tests`が持ち、ここは値の記録だけを担う。

use blitz_math::{ワールド, 角速度};

use super::gyroscopic_treatment::ジャイロ項の扱い;
use super::prediction_tests::予測の角速度で回した角運動量の比;
use super::reference_test_fixtures::{
    判断8の刻み幅の秒, 局所の中間軸の角速度, 自由回転の参照計算, 角速度を作る, 角運動量の大きさ
};
use super::substep_count::細分数;

fn 細分ごとの角運動量の比(
    初期角速度: 角速度<ワールド>, 刻み幅の秒: f32, 扱い: ジャイロ項の扱い, 細分の数: u32
) -> Vec<f32> {
    let mut 参照計算 = 自由回転の参照計算(初期角速度, 刻み幅の秒, 扱い);
    let 初期値 = 角運動量の大きさ(&参照計算.台帳().剛体一覧()[0]);
    (0..細分の数)
        .map(|_| {
            参照計算
                .一刻み進める(細分数::生成する(1).unwrap_or_else(|誤り| panic!("{誤り}")))
                .unwrap_or_else(|誤り| panic!("{誤り}"));
            角運動量の大きさ(&参照計算.台帳().剛体一覧()[0]) / 初期値
        })
        .collect()
}

#[test]
fn 判断8の観測値を印字する() {
    let 最後 = |比: &[f32]| 比.last().copied().unwrap_or(f32::NAN);
    let 粗い = 細分ごとの角運動量の比(角速度を作る(3.0, 7.0, 5.0), 判断8の刻み幅の秒, ジャイロ項の扱い::陰的に一段解く, 600);
    let 細かい = 細分ごとの角運動量の比(
        角速度を作る(3.0, 7.0, 5.0),
        判断8の刻み幅の秒 / 2.0,
        ジャイロ項の扱い::陰的に一段解く,
        1200,
    );
    println!(
        "自由回転(3,7,5)の角運動量の比: 1/480秒×600細分={:.5}, 1/960秒×1200細分={:.5}",
        最後(&粗い),
        最後(&細かい)
    );
    let 最大 = 粗い.iter().copied().fold(0.0f32, f32::max);
    println!("自由回転(3,7,5)の600細分の間の比の最大={最大:.5}");
    for 扱い in [ジャイロ項の扱い::陰的に一段解く, ジャイロ項の扱い::省く] {
        let mut 参照計算 = 自由回転の参照計算(角速度を作る(0.01, 10.0, 0.0), 判断8の刻み幅の秒, 扱い);
        let 反転 = (1..=4000u32).find(|_| {
            参照計算
                .一刻み進める(細分数::生成する(1).unwrap_or_else(|誤り| panic!("{誤り}")))
                .unwrap_or_else(|誤り| panic!("{誤り}"));
            局所の中間軸の角速度(&参照計算.台帳().剛体一覧()[0]) < 0.0
        });
        println!("中間軸(0.01,10,0)の反転の細分({扱い:?}): {反転:?}");
    }
    let 陽的の全体 = 細分ごとの角運動量の比(角速度を作る(0.0, 200.0, 150.0), 判断8の刻み幅の秒, ジャイロ項の扱い::陽的に足す, 100);
    let 陰的の全体 = 細分ごとの角運動量の比(角速度を作る(0.0, 200.0, 150.0), 判断8の刻み幅の秒, ジャイロ項の扱い::陰的に一段解く, 100);
    println!(
        "高速回転(0,200,150)を再構成を通した全体の経路で100細分: 陽的の最大={:.4} 最後={:.4}, 陰的の最後={:.4}",
        陽的の全体.iter().copied().fold(0.0f32, f32::max),
        最後(&陽的の全体),
        最後(&陰的の全体)
    );
    let 初期値 = 角運動量の大きさ(
        &自由回転の参照計算(角速度を作る(0.0, 200.0, 150.0), 判断8の刻み幅の秒, ジャイロ項の扱い::陰的に一段解く)
            .台帳()
            .剛体一覧()[0],
    );
    let 陽的 = 予測の角速度で回した角運動量の比(ジャイロ項の扱い::陽的に足す, 初期値);
    let 越えた細分 = 陽的.iter().position(|比| !比.is_finite() || *比 > 2.0).map(|添字| 添字 + 1);
    let 陰的 = 予測の角速度で回した角運動量の比(ジャイロ項の扱い::陰的に一段解く, 初期値);
    println!(
        "高速回転(0,200,150)を予測だけで100細分: 陽的が2倍を越えた細分={越えた細分:?} 最後={:?}, 陰的の最後={:.4}",
        最後(&陽的),
        最後(&陰的)
    );
}
