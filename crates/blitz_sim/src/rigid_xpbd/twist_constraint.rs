//! 隣接する姿勢の相対ねじりを制約する拘束(判断10の3つ目。剛体と剛体。回転だけ)。棒のねじり(Issue #9)と関節(Issue #41)の基礎である。
//!   q_相対 = q_A⁻¹ ⊗ q_B(A の重心局所座標で表した B の姿勢)、q_誤差 = q_相対 ⊗ q_静止⁻¹
//!   Δ_A = 2·vec(q_誤差)(A局所座標の回転ベクトル。実部が負なら反転)、C = Δ_A · ā(ā は共有する軸を A局所座標で表した単位ベクトル)
//!   勾配の向きはワールドへ写した n = R(q_A) ā であり、A の勾配は −n、B の勾配は +n、w̃ = nᵀ I⁻¹ n(回転だけの形)
//!   Δλ = (−C − α̃λ) ÷ (w̃_A + w̃_B + α̃)、補正は Δq = (1/2)·[I⁻¹ (Δλ (∓n))]_四元数 ⊗ q(判断9)
//! 拘束違反をA局所座標で閉じて計算し勾配だけをワールドへ写すのは、相対姿勢の回転ベクトルと軸を同じ座標系で内積するためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断10」。

use blitz_math::{クォータニオン, ローカル, 方向, 逆キログラム平方メートル};

use super::participant::姿勢自由度の参加者;
use super::rotational_compliance::{回転のコンプライアンス, 回転のコンプライアンスエラー};
use super::rotational_lagrange_multiplier::回転のラグランジュ乗数;
use super::twist_result::ねじり拘束の一回の射影の結果;
use crate::xpbd::刻み幅;

/// 静的な引数: 静止の相対姿勢(A局所で表したBの姿勢の基準)・共有する軸(A局所)・コンプライアンス。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ねじり拘束の引数 {
    pub 静止の相対姿勢: クォータニオン<ローカル, ローカル>,
    pub 軸: 方向<ローカル>,
    pub コンプライアンス: 回転のコンプライアンス,
}

impl ねじり拘束の引数 {
    pub fn 生成する(
        静止の相対姿勢: クォータニオン<ローカル, ローカル>, 軸: 方向<ローカル>, コンプライアンス: 回転のコンプライアンス
    ) -> Self {
        Self {
            静止の相対姿勢,
            軸,
            コンプライアンス,
        }
    }

    pub fn 刻み幅で解く係数を導く(
        &self,
        刻み幅: 刻み幅,
    ) -> Result<ねじり拘束の一刻みの係数, 回転のコンプライアンスエラー> {
        Ok(ねじり拘束の一刻みの係数 {
            静止の相対姿勢の逆: self.静止の相対姿勢.逆回転(),
            軸: self.軸,
            刻み依存量: self.コンプライアンス.刻み依存量(刻み幅)?,
        })
    }
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ねじり拘束の一刻みの係数 {
    静止の相対姿勢の逆: クォータニオン<ローカル, ローカル>,
    軸: 方向<ローカル>,
    刻み依存量: 逆キログラム平方メートル,
}

impl ねじり拘束の一刻みの係数 {
    /// 正典式の1回の反復。呼び出し側は2つの補正を各剛体の予測の状態へ適用し、更新後の乗数を次の反復へ渡す。
    pub fn 一回射影する(
        &self,
        a: &姿勢自由度の参加者,
        b: &姿勢自由度の参加者,
        乗数: 回転のラグランジュ乗数,
    ) -> ねじり拘束の一回の射影の結果 {
        if a.動かせないか() && b.動かせないか() {
            return ねじり拘束の一回の射影の結果::両方が動かせない;
        }
        let 相対 = a.配置().姿勢().相手の姿勢を自分の局所で表す(b.配置().姿勢());
        let 誤差 = self.静止の相対姿勢の逆.続けて回す(&相対);
        let 拘束違反 = 誤差.微小回転として回転ベクトルへ().方向に沿う成分(self.軸);
        let 向き = a.配置().姿勢().回転().方向を回す(self.軸);
        let 有効逆慣性 = a.回転だけの一般化逆質量(向き) + b.回転だけの一般化逆質量(向き);
        let 乗数の増分 = 回転のラグランジュ乗数::角を逆慣性で割って生成する(
            (拘束違反 + 乗数 * self.刻み依存量) * -1.0,
            有効逆慣性 + self.刻み依存量,
        );
        ねじり拘束の一回の射影の結果::補正した {
            補正a: a.回転に作用する乗数を補正へ分配する(向き.逆を向く方向(), 乗数の増分),
            補正b: b.回転に作用する乗数を補正へ分配する(向き, 乗数の増分),
            更新後のラグランジュ乗数: 乗数 + 乗数の増分,
        }
    }
}
