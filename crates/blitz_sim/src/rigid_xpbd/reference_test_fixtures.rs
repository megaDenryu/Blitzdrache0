//! 姿勢自由度の検査の材料。主慣性(1, 2, 3)の質量特性・位置と変位と角速度の生成・予測器と参照計算の組み立て・角運動量の大きさの観測を持つ。
//! 判断8の検査が主慣性(1, 2, 3)[kg·m²]と細分の刻み幅1/480秒を指定しているため、その値をここに1箇所で置く。

use blitz_math::{
    キログラム, キログラム平方メートル, クォータニオン, メートル, メートル毎秒毎秒, ラジアン毎秒, ローカル, ワールド, 位置, 変位, 秒, 角速度,
};

use super::gyroscopic_treatment::ジャイロ項の扱い;
use super::predictor::細分の予測器;
use super::reference::{剛体の参照計算, 剛体の拘束の一覧};
use super::substep_count::細分数;
use crate::rigid_body::{
    主慣性, 主慣性と主軸, 剛体, 剛体の台帳, 剛体の識別子, 姿勢, 質量特性, 運動状態, 運動種別, 配置
};
use crate::xpbd::刻み幅;

pub(super) const 判断8の刻み幅の秒: f32 = 1.0 / 480.0;

fn 材料を作る<値, 誤り: std::fmt::Display>(結果: Result<値, 誤り>) -> 値 {
    結果.unwrap_or_else(|誤り| panic!("検査の材料を作れない: {誤り}"))
}

/// 主慣性(第一, 第二, 第三)で主軸が局所の軸そのものの質量特性。重心は物体原点に置く。
pub(super) fn 質量特性を作る(質量: f32, 第一: f32, 第二: f32, 第三: f32) -> 質量特性 {
    let [a, b, c] = [第一, 第二, 第三].map(キログラム平方メートル::生成する);
    let 主慣性と主軸 = 材料を作る(主慣性と主軸::生成する(
        主慣性::生成する(a, b, c),
        クォータニオン::軸が一致する回転(),
    ));
    材料を作る(質量特性::生成する(
        材料を作る(キログラム::生成する(質量)),
        変位::零(),
        主慣性と主軸,
    ))
}

pub(super) fn 主慣性123の質量特性(質量: f32) -> 質量特性 {
    質量特性を作る(質量, 1.0, 2.0, 3.0)
}

pub(super) fn 位置を作る(x: f32, y: f32, z: f32) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

pub(super) fn 局所の変位を作る(x: f32, y: f32, z: f32) -> 変位<ローカル> {
    変位::成分から生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

pub(super) fn 角速度を作る(x: f32, y: f32, z: f32) -> 角速度<ワールド> {
    角速度::成分から生成する(ラジアン毎秒::生成する(x), ラジアン毎秒::生成する(y), ラジアン毎秒::生成する(z))
}

pub(super) fn 原点の配置() -> 配置 {
    配置::生成する(位置を作る(0.0, 0.0, 0.0), 姿勢::恒等())
}

pub(super) fn 予測器を作る(刻み幅の秒: f32, 重力: f32, 扱い: ジャイロ項の扱い) -> 細分の予測器 {
    let 零 = メートル毎秒毎秒::生成する(0.0);
    let 加速度 = crate::constraint_graph::一様な加速度::成分から生成する(零, メートル毎秒毎秒::生成する(重力), 零);
    細分の予測器::生成する(材料を作る(刻み幅::生成する(秒::生成する(刻み幅の秒))), 加速度, 扱い)
}

/// 静止から始める動的剛体を登録して識別子を返す。
pub(super) fn 動的剛体を登録する(台帳: &mut 剛体の台帳, 配置: 配置, 質量特性: 質量特性) -> 剛体の識別子 {
    材料を作る(台帳.登録する(配置, 質量特性, 運動種別::動的で始める(運動状態::静止())))
}

/// 動的剛体1つだけの台帳。拘束を持たない参照計算が自由回転の題材になる。
pub(super) fn 自由回転の参照計算(
    初期角速度: 角速度<ワールド>, 刻み幅の秒: f32, 扱い: ジャイロ項の扱い
) -> 剛体の参照計算 {
    let mut 台帳 = 剛体の台帳::空();
    let 運動状態 = 運動状態::生成する(blitz_math::速度::零(), 初期角速度);
    材料を作る(台帳.登録する(原点の配置(), 主慣性123の質量特性(1.0), 運動種別::動的で始める(運動状態)));
    let 予測器 = 予測器を作る(刻み幅の秒, 0.0, 扱い);
    材料を作る(剛体の参照計算::生成する(台帳, &[], 剛体の拘束の一覧::空(), 予測器, 1))
}

/// 重力なし・基本刻み1/60秒を4細分・反復8回で拘束を解く参照計算を組み、1刻み進めた後の台帳を返す。
pub(super) fn 拘束を1刻み解いた台帳(台帳: 剛体の台帳, 拘束: 剛体の拘束の一覧) -> 剛体の参照計算 {
    let 予測器 = 予測器を作る(1.0 / 240.0, 0.0, ジャイロ項の扱い::陰的に一段解く);
    let mut 参照計算 = 材料を作る(剛体の参照計算::生成する(台帳, &[], 拘束, 予測器, 8));
    材料を作る(参照計算.一刻み進める(材料を作る(細分数::生成する(4))));
    参照計算
}

pub(super) fn 剛体を参照する(参照計算: &剛体の参照計算, 識別子: 剛体の識別子) -> &剛体 {
    材料を作る(参照計算.台帳().参照する(識別子))
}

/// ワールド座標の角運動量 R(q) I_ℓ R(q)ᵀ ω の大きさ。局所へ回した角速度に局所の慣性を掛けた長さと同じである。
pub(super) fn 角運動量の大きさ(剛体: &剛体) -> f32 {
    let 局所の角速度 = 剛体.配置().姿勢().逆回転().角速度を回す(材料を作る(剛体.速度()).角速度());
    剛体
        .質量特性()
        .主慣性と主軸()
        .局所の慣性テンソル()
        .角速度を角運動量へ写す(局所の角速度)
        .長さ()
        .値()
}

/// 局所座標の角速度の第二成分(中間軸の成分)。
pub(super) fn 局所の中間軸の角速度(剛体: &剛体) -> f32 {
    剛体.配置().姿勢().逆回転().角速度を回す(材料を作る(剛体.速度()).角速度()).y().値()
}
