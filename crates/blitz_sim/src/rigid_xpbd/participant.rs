//! 姿勢自由度の参加者: 拘束の射影が読む剛体の3つの量(配置・逆質量・ワールドの逆慣性)。点自由度の`距離拘束の参加点`に対応する。
//! 静的と運動学的の剛体は「動かせない」参加者として逆質量0と零の逆慣性を持つ。これは解法の内部の実効の重みであり、質量の正本を0で表す意味ではない(判断2・判断9)。
//! 一般化逆質量 w̃ = w + (r × n)ᵀ I⁻¹ (r × n) と、回転だけの拘束の w̃ = nᵀ I⁻¹ n をここが求める。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断9」「判断10」。

use blitz_math::{ワールド, 変位, 方向, 逆キログラム, 逆キログラム平方メートル, 逆慣性テンソル};

use crate::rigid_body::{質量特性, 配置};

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 姿勢自由度の参加者 {
    配置: 配置,
    逆質量: 逆キログラム,
    ワールドの逆慣性: 逆慣性テンソル<ワールド>,
}

impl 姿勢自由度の参加者 {
    /// 動的剛体。ワールドの逆慣性 I⁻¹ = R(q) I_ℓ⁻¹ R(q)ᵀ をこの配置で組む(判断4)。
    pub fn 動的(配置: 配置, 質量特性: &質量特性) -> Self {
        Self {
            配置,
            逆質量: 質量特性.逆質量(),
            ワールドの逆慣性: 配置.姿勢().回転().逆慣性テンソルを回す(質量特性.主慣性と主軸().局所の逆慣性テンソル()),
        }
    }

    /// 静的または運動学的の剛体。実効の重み0であり、補正を受けない。
    pub fn 動かせない(配置: 配置) -> Self {
        Self {
            配置,
            逆質量: 逆キログラム::零(),
            ワールドの逆慣性: 逆慣性テンソル::零(),
        }
    }

    pub fn 配置(&self) -> &配置 {
        &self.配置
    }

    pub fn 逆質量(&self) -> 逆キログラム {
        self.逆質量
    }

    pub fn ワールドの逆慣性(&self) -> &逆慣性テンソル<ワールド> {
        &self.ワールドの逆慣性
    }

    pub fn 動かせないか(&self) -> bool {
        self.逆質量.零か()
    }

    /// 腕 r の点に向き n で作用する拘束の一般化逆質量 w + (r × n)ᵀ I⁻¹ (r × n)。
    pub fn 一般化逆質量(&self, 腕: 変位<ワールド>, 向き: 方向<ワールド>) -> 逆キログラム {
        self.逆質量 + self.ワールドの逆慣性.腕と向きの一般化逆質量の寄与(腕, 向き)
    }

    /// 軸 n のまわりの回転だけに作用する拘束の一般化逆質量 nᵀ I⁻¹ n。
    pub fn 回転だけの一般化逆質量(&self, 向き: 方向<ワールド>) -> 逆キログラム平方メートル {
        self.ワールドの逆慣性.向きの一般化逆質量(向き)
    }
}
