//! 姿勢自由度の参加者: 拘束の射影が読む剛体の3つの量(配置・逆質量・ワールドの逆慣性)。点自由度の`距離拘束の参加点`に対応する。
//! 静的と運動学的の剛体は「動かせない」参加者として逆質量0と零の逆慣性を持つ。これは解法の内部の実効の重みであり、質量の正本を0で表す意味ではない(判断2・判断9)。
//! 一般化逆質量 w̃ = w + (r × n)ᵀ I⁻¹ (r × n) と、回転だけの拘束の w̃ = nᵀ I⁻¹ n をここが求める。
//! 乗数の増分 Δλ を並進の補正と回転の補正へ分配する式もここが持つ(補正は逆質量と逆慣性から決まる)。CPUの参照計算の正典であり、GPUの写しは同じ符号・同じ演算順で書く。
//!   点に作用する拘束:   Δx = w · Δλ · n、Δq = (1/2)·[ I⁻¹ (r × (Δλ n)) ]_四元数 ⊗ q
//!   回転だけの拘束:     Δq = (1/2)·[ I⁻¹ (Δλ n) ]_四元数 ⊗ q
//! n はその剛体の勾配の向きであり、aからbへ向かう n に対して a の勾配は −n である(距離拘束の規約と同じ)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断9」「判断10」。

use blitz_math::{
    ワールド, 変位, 方向, 符号付き逆キログラム, 逆キログラム, 逆キログラム平方メートル, 逆慣性テンソル
};

use super::correction::姿勢自由度の補正;
use super::rotational_lagrange_multiplier::回転のラグランジュ乗数;
use crate::rigid_body::{質量特性, 配置};
use crate::xpbd::ラグランジュ乗数;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 姿勢自由度の参加者 {
    配置: 配置,
    逆質量: 逆キログラム,
    ワールドの逆慣性: 逆慣性テンソル<ワールド>,
}

impl 姿勢自由度の参加者 {
    /// 動的剛体。ワールドの逆慣性 I⁻¹ = R(q) I_ℓ⁻¹ R(q)ᵀ をこの配置で組む(判断4)。
    pub fn 動的(配置: 配置, 質量特性: &質量特性) -> Self {
        Self {
            配置,
            逆質量: 質量特性.逆質量(),
            ワールドの逆慣性: 配置.姿勢().回転().逆慣性テンソルを回す(質量特性.主慣性と主軸().局所の逆慣性テンソル()),
        }
    }

    /// 静的または運動学的の剛体。実効の重み0であり、補正を受けない。
    pub fn 動かせない(配置: 配置) -> Self {
        Self {
            配置,
            逆質量: 逆キログラム::零(),
            ワールドの逆慣性: 逆慣性テンソル::零(),
        }
    }

    pub fn 配置(&self) -> &配置 {
        &self.配置
    }

    pub fn 逆質量(&self) -> 逆キログラム {
        self.逆質量
    }

    pub fn ワールドの逆慣性(&self) -> &逆慣性テンソル<ワールド> {
        &self.ワールドの逆慣性
    }

    pub fn 動かせないか(&self) -> bool {
        self.逆質量.零か()
    }

    /// 腕 r の点に向き n で作用する拘束の一般化逆質量 w + (r × n)ᵀ I⁻¹ (r × n)。
    pub fn 一般化逆質量(&self, 腕: 変位<ワールド>, 向き: 方向<ワールド>) -> 逆キログラム {
        self.逆質量 + self.ワールドの逆慣性.腕と向きの一般化逆質量の寄与(腕, 向き)
    }

    /// 2つの点に別々の向きで作用する2つの拘束が、この剛体を通して結び付く一般化逆質量の交差の寄与
    /// w (n₁·n₂) + (r₁ × n₁)ᵀ I⁻¹ (r₂ × n₂)。同じ組を2度渡せば `一般化逆質量` に一致する。
    /// 接触点集合の法線を同時に解く有効逆質量行列の成分がこの量であり、符号を持つ(判断12)。
    pub fn 二つの点の一般化逆質量の交差の寄与(
        &self,
        第1の腕: 変位<ワールド>,
        第1の向き: 方向<ワールド>,
        第2の腕: 変位<ワールド>,
        第2の向き: 方向<ワールド>,
    ) -> 符号付き逆キログラム {
        符号付き逆キログラム::逆質量から生成する(self.逆質量).比で伸ばす(第1の向き.なす角の余弦(&第2の向き))
            + self
                .ワールドの逆慣性
                .二つの腕と向きの一般化逆質量の交差の寄与(第1の腕, 第1の向き, 第2の腕, 第2の向き)
    }

    /// 腕 r の点に向き n で作用する拘束の一般化逆質量の上界 w + |(I⁻¹ (r × n)) × r|。
    /// 補正を有限回転として適用したとき、乗数の増分1あたりにこの点が向き n の側へ実際に動く長さはこの値を超えない。
    /// 片側拘束が1細分に詰めてよい長さを守るときは、線形化した一般化逆質量でなくこの上界で長さと乗数を換算する(判断12)。
    pub fn 一般化逆質量の上界(&self, 腕: 変位<ワールド>, 向き: 方向<ワールド>) -> 逆キログラム {
        self.逆質量 + self.ワールドの逆慣性.腕と向きの一般化逆質量の回転の寄与の上界(腕, 向き)
    }

    /// 軸 n のまわりの回転だけに作用する拘束の一般化逆質量 nᵀ I⁻¹ n。
    pub fn 回転だけの一般化逆質量(&self, 向き: 方向<ワールド>) -> 逆キログラム平方メートル {
        self.ワールドの逆慣性.向きの一般化逆質量(向き)
    }

    /// 腕 r の点に勾配の向き n で乗数の増分 Δλ が作用したときにこの剛体が受ける補正。Δx = w Δλ n、Δθ = I⁻¹ (r × (Δλ n))。
    pub fn 点に作用する乗数を補正へ分配する(
        &self,
        腕: 変位<ワールド>,
        勾配の向き: 方向<ワールド>,
        乗数の増分: ラグランジュ乗数,
    ) -> 姿勢自由度の補正 {
        姿勢自由度の補正::並進と回転から生成する(
            変位::方向へ進む(勾配の向き, 乗数の増分 * self.逆質量),
            self.ワールドの逆慣性
                .腕に作用する乗数の回転(腕, 勾配の向き, 乗数の増分.キログラムメートル()),
        )
    }

    /// 軸 n のまわりの回転だけに乗数の増分 Δλ が作用したときにこの剛体が受ける補正。Δθ = I⁻¹ (Δλ n)、並進は零。
    pub fn 回転に作用する乗数を補正へ分配する(
        &self,
        勾配の向き: 方向<ワールド>,
        乗数の増分: 回転のラグランジュ乗数,
    ) -> 姿勢自由度の補正 {
        姿勢自由度の補正::並進と回転から生成する(
            変位::零(),
            self.ワールドの逆慣性
                .向きに作用する回転の乗数の回転(勾配の向き, 乗数の増分.キログラム平方メートル()),
        )
    }
}
