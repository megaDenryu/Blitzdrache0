//! 判断10のねじり拘束の収束の検査。軸まわりの相対角が静止角へ収束すること・慣性が等方なら軸の傾き(軸に垂直な回転)が変わらないこと・
//! 静止の相対姿勢が恒等でなくても静止角へ収束し両方が動的なら両方が回ることを固定する。
//! 軸の傾きが変わらないのは慣性が等方のときに限る。補正の回転の軸は I⁻¹ n であり、慣性が異方だと n から傾くためである(判断9の式の性質)。

#![allow(clippy::unwrap_used)]

use blitz_math::{クォータニオン, ラジアン, ローカル, ワールド, 方向};

use super::reference::{剛体の参照計算, 剛体の拘束の一覧, 添字付きねじり拘束};
use super::reference_test_fixtures::{
    主慣性123の質量特性, 位置を作る, 剛体を参照する, 動的剛体を登録する, 原点の配置, 拘束を1刻み解いた台帳, 質量特性を作る,
};
use super::twist_test_fixtures::{x軸のねじり拘束, 回転ベクトルを作る, 姿勢を作る};
use crate::rigid_body::{剛体の台帳, 剛体の識別子, 姿勢, 質量特性, 運動種別, 配置};

/// 剛体の共有する軸(局所x)が世界のx軸となす傾き。
fn 軸の傾き(姿勢: &姿勢) -> f32 {
    let bの軸 = 姿勢.回転().方向を回す(方向::<ローカル>::生成する(1.0, 0.0, 0.0).unwrap());
    bの軸.内積(&方向::<ワールド>::生成する(1.0, 0.0, 0.0).unwrap()).acos()
}

/// 静止した剛体Aに対して、Bを傾いた軸(0.3, 0.2, 0)の回転ベクトルで回して置き、静止角0のねじり拘束で1刻み解く。
fn 静止したaへbをねじって置く(bの質量特性: 質量特性) -> (剛体の参照計算, 剛体の識別子, 剛体の識別子) {
    let mut 台帳 = 剛体の台帳::空();
    let a = 台帳.登録する(原点の配置(), 主慣性123の質量特性(1.0), 運動種別::静的).unwrap();
    let b = 動的剛体を登録する(
        &mut 台帳,
        配置::生成する(位置を作る(1.0, 0.0, 0.0), 姿勢を作る(回転ベクトルを作る(0.3, 0.2, 0.0))),
        bの質量特性,
    );
    let 拘束 = vec![添字付きねじり拘束 {
        剛体a: a,
        剛体b: b,
        引数: x軸のねじり拘束(クォータニオン::恒等()),
    }];
    (
        拘束を1刻み解いた台帳(
            台帳,
            剛体の拘束の一覧 {
                ねじり拘束: 拘束,
                ..剛体の拘束の一覧::空()
            },
        ),
        a,
        b,
    )
}

fn 軸まわりの相対角(参照計算: &剛体の参照計算, a: 剛体の識別子, b: 剛体の識別子) -> f32 {
    let 相対 = 剛体を参照する(参照計算, a)
        .配置()
        .姿勢()
        .相手の姿勢を自分の局所で表す(剛体を参照する(参照計算, b).配置().姿勢());
    相対.微小回転として回転ベクトルへ().x().値()
}

#[test]
fn 軸まわりの相対角は静止角へ収束し等方な慣性では軸の傾きが変わらない() {
    let 等方 = 質量特性を作る(1.0, [2.0, 2.0, 2.0]);
    let 初期の傾き = 軸の傾き(&姿勢を作る(回転ベクトルを作る(0.3, 0.2, 0.0)));
    let (参照計算, a, b) = 静止したaへbをねじって置く(等方);
    assert!(
        軸まわりの相対角(&参照計算, a, b).abs() < 1.0e-4,
        "相対角{}",
        軸まわりの相対角(&参照計算, a, b)
    );
    let 傾き = 軸の傾き(剛体を参照する(&参照計算, b).配置().姿勢());
    assert!(
        初期の傾き > 0.1 && (傾き - 初期の傾き).abs() < 1.0e-4,
        "傾き{傾き}が初期の{初期の傾き}から変わった"
    );
    let (異方, a, b) = 静止したaへbをねじって置く(主慣性123の質量特性(1.0));
    assert!(軸まわりの相対角(&異方, a, b).abs() < 1.0e-4, "異方な慣性でも軸まわりの相対角は収束する");
}

#[test]
fn 静止の相対姿勢が恒等でなくても軸まわりの相対角は静止角へ収束し両方が動的なら両方が回る() {
    let 静止 = クォータニオン::<ローカル, ローカル>::回転ベクトルから生成する(blitz_math::回転ベクトル::成分から生成する(
        ラジアン::生成する(0.5),
        ラジアン::生成する(0.0),
        ラジアン::生成する(0.0),
    ));
    let mut 台帳 = 剛体の台帳::空();
    let a = 動的剛体を登録する(&mut 台帳, 原点の配置(), 主慣性123の質量特性(1.0));
    let b = 動的剛体を登録する(
        &mut 台帳,
        配置::生成する(位置を作る(1.0, 0.0, 0.0), 姿勢::恒等()),
        主慣性123の質量特性(2.0),
    );
    let 拘束 = vec![添字付きねじり拘束 {
        剛体a: a,
        剛体b: b,
        引数: x軸のねじり拘束(静止),
    }];
    let 参照計算 = 拘束を1刻み解いた台帳(
        台帳,
        剛体の拘束の一覧 {
            ねじり拘束: 拘束,
            ..剛体の拘束の一覧::空()
        },
    );
    let 相対 = 剛体を参照する(&参照計算, a)
        .配置()
        .姿勢()
        .相手の姿勢を自分の局所で表す(剛体を参照する(&参照計算, b).配置().姿勢());
    assert!((相対.対数写像で回転ベクトルへ().x().値() - 0.5).abs() < 1.0e-4, "相対{相対:?}");
    let 回ったa = 剛体を参照する(&参照計算, a).配置().姿勢().回転().対数写像で回転ベクトルへ().x().値();
    assert!(回ったa < 0.0, "両方が動的ならAも逆向きへ回る: {回ったa}");
}
