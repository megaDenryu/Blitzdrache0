//! 細分の予測器: 細分1本の刻み幅と重力を保持し、動的剛体の配置と運動状態と一刻みの入力から前の状態と予測の状態を作る(判断8)。
//! 順は速度→位置→角速度(局所座標でジャイロ項)→回転力→姿勢(1次の更新と正規化)である。
//!   v ← v + h (g + w F)、x ← x + h v
//!   ω_ℓ = R(q)ᵀ ω、ω₁ = ジャイロ項の扱い(ω_ℓ)、ω₁ ← ω₁ + h I_ℓ⁻¹ τ_ℓ、ω ← R(q) ω₁
//!   q ← q + (h/2)·(ω_四元数 ⊗ q) を正規化(姿勢の型の生成が行う)
//! 運動学的剛体は判断7の細分の配置へ進み(Issue #40)、静的剛体は何もしない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断8」。

use blitz_math::{ワールド, 変位, 角速度, 速度};

use super::gyroscopic_treatment::ジャイロ項の扱い;
use super::predicted_state::予測の状態;
use super::previous_state::前の状態;
use crate::constraint_graph::一様な加速度;
use crate::rigid_body::{一刻みの入力, 質量特性, 運動状態, 配置};
use crate::xpbd::刻み幅;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 細分の予測器 {
    刻み幅: 刻み幅,
    重力: 一様な加速度,
    ジャイロ項の扱い: ジャイロ項の扱い,
}

impl 細分の予測器 {
    pub fn 生成する(刻み幅: 刻み幅, 重力: 一様な加速度, ジャイロ項の扱い: ジャイロ項の扱い) -> Self {
        Self {
            刻み幅,
            重力,
            ジャイロ項の扱い,
        }
    }

    pub fn 刻み幅(&self) -> 刻み幅 {
        self.刻み幅
    }

    /// 静止した点自由度がこの細分に重力で動く変位(点の予測が読む)。
    pub fn 重力の一刻みの変位(&self) -> 変位<ワールド> {
        self.重力.一刻みの変位(self.刻み幅)
    }

    /// 動的剛体の細分1本の予測。前の状態(保存)と予測の状態(補正が掛かる)と、予測の速度(拘束が無ければ再構成がこれへ戻る)を返す。
    pub fn 動的剛体を予測する(
        &self,
        配置: &配置,
        運動状態: &運動状態,
        質量特性: &質量特性,
        入力: &一刻みの入力,
    ) -> (前の状態, 予測の状態, 運動状態) {
        let h = self.刻み幅.秒();
        let 並進速度: 速度<ワールド> = 運動状態.並進速度() + self.重力.一刻みの速度の変化(self.刻み幅) + (入力.合力() * h) * 質量特性.逆質量();
        let 角速度 = self.角速度を予測する(配置, 運動状態.角速度(), 質量特性, 入力);
        let 予測の配置 = 配置.並進で動かす(並進速度 * h).微小回転で回す(角速度 * h);
        (
            前の状態::配置から保存する(配置),
            予測の状態::生成する(予測の配置),
            運動状態::生成する(並進速度, 角速度),
        )
    }

    fn 角速度を予測する(
        &self, 配置: &配置, 角速度: 角速度<ワールド>, 質量特性: &質量特性, 入力: &一刻みの入力
    ) -> 角速度<ワールド> {
        let 慣性 = 質量特性.主慣性と主軸();
        let 局所の角速度 = 配置.姿勢().逆回転().角速度を回す(角速度);
        let ジャイロ項を進めた = self
            .ジャイロ項の扱い
            .局所の角速度を進める(局所の角速度, 慣性.局所の慣性テンソル(), self.刻み幅.秒());
        let 局所の回転力 = 配置.姿勢().逆回転().回転力を回す(入力.合回転力());
        let 回転力を足した = ジャイロ項を進めた + 慣性.局所の逆慣性テンソル().回転衝撃を角速度へ写す(局所の回転力 * self.刻み幅.秒());
        配置.姿勢().回転().角速度を回す(回転力を足した)
    }
}
