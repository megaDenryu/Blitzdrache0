//! 速度の再構成だけが読む仮の補正の試験(判断24の反証(d)の一部)。担当するのは2つの性質を固定することである。
//! 補正が零の細分では速度の再構成が判断9の従来の式とビットで一致すること、零でない補正を渡すと再構成した速度が
//! その補正のぶんだけ動くことである。
//! ビット一致を型の側で保つのは、姿勢へ零の微小回転を掛ける経路が正規化を通るためである。値が変わる保証も
//! 変わらない保証も無い経路を速度の正本へ通してはならない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 位置, 回転ベクトル, 変位, 方向, 秒};

use super::correction::姿勢自由度の補正;
use super::previous_state::前の状態;
use super::velocity_only_correction::速度の再構成だけが読む仮の補正;
use crate::rigid_body::{姿勢, 配置};
use crate::xpbd::刻み幅;

const 細分の刻み幅の秒: f32 = 1.0 / 480.0;
const 除く長さ: f32 = 2.0e-6;

fn 高さの配置(高さ: f32) -> 配置 {
    配置::生成する(
        位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(高さ), メートル::生成する(0.0)),
        姿勢::恒等(),
    )
}

fn 試験の刻み幅() -> 刻み幅 {
    刻み幅::生成する(秒::生成する(細分の刻み幅の秒)).unwrap()
}

#[test]
fn 補正が零なら速度の再構成は判断9の従来の式とビットで一致する() {
    let 前 = 前の状態::配置から保存する(&高さの配置(0.0));
    let 確定 = 高さの配置(1.0e-3);
    let 従来 = 前.確定した配置から速度を再構成する(&確定, 試験の刻み幅());
    let 仮の補正あり =
        前.確定した配置と仮の補正から速度を再構成する(&確定, &速度の再構成だけが読む仮の補正::零(), 試験の刻み幅());
    assert_eq!(従来, 仮の補正あり);
}

#[test]
fn 零でない補正は再構成した速度をその補正のぶんだけ動かす() {
    let 前 = 前の状態::配置から保存する(&高さの配置(0.0));
    let 確定 = 高さの配置(1.0e-3);
    let 動かす =
        速度の再構成だけが読む仮の補正::残差の変化を打ち消す補正を包む(姿勢自由度の補正::並進と回転から生成する(
            変位::方向へ進む(方向::生成する(0.0, 1.0, 0.0).unwrap(), メートル::生成する(除く長さ)),
            回転ベクトル::零(),
        ));
    let 動いた = 前.確定した配置と仮の補正から速度を再構成する(&確定, &動かす, 試験の刻み幅());
    let 従来 = 前.確定した配置から速度を再構成する(&確定, 試験の刻み幅());
    let 差 = 動いた.並進速度().y().値() - 従来.並進速度().y().値();
    assert!((差 - 除く長さ / 細分の刻み幅の秒).abs() < 1.0e-6);
}
