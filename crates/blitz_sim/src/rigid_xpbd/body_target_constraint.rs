//! 剛体の局所点を世界の目標点へ一致させる拘束(判断10の1つ目。剛体と世界の点)。既存の目標拘束(点自由度)の姿勢自由度への一般化である。
//!   p = x + R(q) r̄、r = p − x、d = 目標 − p、C = |d|、n = d ÷ C(pから目標へ向かう単位向き)
//!   w̃ = w + (r × n)ᵀ I⁻¹ (r × n)、Δλ = (−C − α̃λ) ÷ (w̃ + α̃)
//!   剛体の勾配は −n であり、補正は Δx = w Δλ (−n)、Δq = (1/2)·[I⁻¹ (r × (Δλ (−n)))]_四元数 ⊗ q(判断9)
//! 退化(剛体が動かせない・pが目標と一致)は非数を作らずに理由の枝を返し、λは変えない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断9」「判断10」。

use blitz_math::{ローカル, ワールド, 位置, 変位, 逆キログラム};

use super::body_target_result::剛体の目標拘束の一回の射影の結果;
use super::correction::姿勢自由度の補正;
use super::participant::姿勢自由度の参加者;
use crate::xpbd::{
    コンプライアンス, コンプライアンスエラー, ラグランジュ乗数, 刻み幅, 向きが定まる最小の距離
};

/// 静的な引数: 剛体の局所点とコンプライアンス。目標位置は毎刻み与える入力であり、ここには持たない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 剛体の目標拘束の引数 {
    pub 局所点: 変位<ローカル>,
    pub コンプライアンス: コンプライアンス,
}

impl 剛体の目標拘束の引数 {
    pub fn 生成する(局所点: 変位<ローカル>, コンプライアンス: コンプライアンス) -> Self {
        Self {
            局所点, コンプライアンス
        }
    }

    /// 細分の開始時に1度だけ導く係数。
    pub fn 刻み幅で解く係数を導く(
        &self,
        刻み幅: 刻み幅,
    ) -> Result<剛体の目標拘束の一刻みの係数, コンプライアンスエラー> {
        Ok(剛体の目標拘束の一刻みの係数 {
            局所点: self.局所点,
            刻み依存量: self.コンプライアンス.刻み依存量(刻み幅)?,
        })
    }
}

/// 1つの刻み幅で解くときの係数。その細分の全反復で同じ値を使う。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 剛体の目標拘束の一刻みの係数 {
    局所点: 変位<ローカル>,
    刻み依存量: 逆キログラム,
}

impl 剛体の目標拘束の一刻みの係数 {
    /// 正典式の1回の反復。呼び出し側は補正を予測の状態へ適用し、更新後の乗数を次の反復へ渡す。
    pub fn 一回射影する(
        &self,
        剛体: &姿勢自由度の参加者,
        目標: 位置<ワールド>,
        乗数: ラグランジュ乗数,
    ) -> 剛体の目標拘束の一回の射影の結果 {
        if 剛体.動かせないか() {
            return 剛体の目標拘束の一回の射影の結果::剛体が動かせない;
        }
        let 腕 = 剛体.配置().腕(self.局所点);
        let 差 = 目標 - 剛体.配置().重心の位置().変位を足す(腕);
        let 拘束違反 = 差.長さ();
        let Ok(向き) = 差.単位方向() else {
            return 剛体の目標拘束の一回の射影の結果::目標と一致している;
        };
        if 拘束違反 < 向きが定まる最小の距離 {
            return 剛体の目標拘束の一回の射影の結果::目標と一致している;
        }
        let 有効逆質量 = 剛体.一般化逆質量(腕, 向き);
        let 乗数の増分 = ラグランジュ乗数::長さを逆質量で割って生成する(
            (拘束違反 + 乗数 * self.刻み依存量) * -1.0,
            有効逆質量 + self.刻み依存量,
        );
        剛体の目標拘束の一回の射影の結果::補正した {
            補正: 姿勢自由度の補正::点に作用する乗数を分配する(剛体, 腕, 向き.逆を向く方向(), 乗数の増分),
            更新後のラグランジュ乗数: 乗数 + 乗数の増分,
        }
    }
}
