const 基本刻みの秒: f32 = 1.0 / 60.0;

fn 剛体1つの参照計算(細分の数: u32) -> (剛体の参照計算, 剛体の識別子) {
    let mut 台帳 = 剛体の台帳::空();
    let 識別子 = 台帳
        .登録する(原点の配置(), 主慣性123の質量特性(2.0), 運動種別::動的で始める(運動状態::静止()))
        .unwrap();
    let 刻み幅の秒 = 基本刻みの秒 / f32::from(u8::try_from(細分の数).unwrap());
    let 予測器 = 予測器を作る(刻み幅の秒, 0.0, ジャイロ項の扱い::陰的に一段解く);
    (剛体の参照計算::生成する(台帳, &[], 剛体の拘束の一覧::空(), 予測器, 1).unwrap(), 識別子)
}

#[test]
fn 一定の力を1刻み加えた運動量の変化は細分数に依らず基本刻みと力の積であり衝撃の変化は衝撃そのものである() {
    for 細分の数 in [4u32, 8, 16] {
        let (mut 参照計算, 識別子) = 剛体1つの参照計算(細分の数);
        let 力 = 力::<ワールド>::成分から生成する(ニュートン::生成する(6.0), ニュートン::生成する(0.0), ニュートン::生成する(0.0));
        参照計算.台帳を書き換える().重心へ力を加える(識別子, 力).unwrap();
        参照計算.一刻み進める(細分数::生成する(細分の数).unwrap()).unwrap();
        let 速度 = 参照計算.台帳().参照する(識別子).unwrap().速度().unwrap().並進速度().x().値();
        let 期待 = 6.0 * 基本刻みの秒 / 2.0;
        assert!((速度 - 期待).abs() < 1.0e-6, "細分数{細分の数}で速度{速度}に対して期待{期待}");
        let (mut 参照計算, 識別子) = 剛体1つの参照計算(細分の数);
        let 衝撃 =
            衝撃::<ワールド>::成分から生成する(ニュートン秒::生成する(0.0), ニュートン秒::生成する(3.0), ニュートン秒::生成する(0.0));
        参照計算.台帳を書き換える().重心へ衝撃を加える(識別子, 衝撃).unwrap();
        参照計算.一刻み進める(細分数::生成する(細分の数).unwrap()).unwrap();
        let 速度 = 参照計算.台帳().参照する(識別子).unwrap().速度().unwrap().並進速度().y().値();
        assert!((速度 - 1.5).abs() < 1.0e-6, "細分数{細分の数}で速度{速度}に対して期待1.5");
    }
}

// 固定した点と、剛体上の局所点を静止長0.5メートルの距離拘束で結ぶ。剛体は重力で落ちて点から静止長だけ離れた位置で釣り合い、点は動かない。
#[test]
fn 点自由度と姿勢自由度は同じ距離拘束へ参加し距離が静止長へ収束する() {
    let mut 台帳 = 剛体の台帳::空();
    let 剛体 = 台帳
        .登録する(原点の配置(), 主慣性123の質量特性(1.0), 運動種別::動的で始める(運動状態::静止()))
        .unwrap();
    let 固定した点 = 点自由度の初期状態::生成する(位置を作る(0.0, 1.0, 0.0), 逆キログラム::零());
    let 引数 = 点と剛体の距離拘束の引数::生成する(
        局所の変位を作る(0.0, 0.2, 0.0),
        静止長::生成する(メートル::生成する(0.5)).unwrap(),
        コンプライアンス::硬い(),
    );
    let 拘束 = vec![添字付き点と剛体の距離拘束 {
        点: 点添字::生成する(0),
        剛体,
        引数,
    }];
    let 予測器 = 予測器を作る(基本刻みの秒 / 8.0, -9.8, ジャイロ項の扱い::陰的に一段解く);
    let 拘束 = 剛体の拘束の一覧 {
        点と剛体の距離拘束: 拘束,
        ..剛体の拘束の一覧::空()
    };
    let mut 参照計算 = 剛体の参照計算::生成する(台帳, &[固定した点], 拘束, 予測器, 4).unwrap();
    for _ in 0..120 {
        参照計算.一刻み進める(細分数::生成する(8).unwrap()).unwrap();
    }
    let 局所点の位置 = 参照計算
        .台帳()
        .参照する(剛体)
        .unwrap()
        .配置()
        .局所点の世界位置(局所の変位を作る(0.0, 0.2, 0.0));
    let 距離 = (局所点の位置 - 位置を作る(0.0, 1.0, 0.0)).長さ().値();
    assert!((距離 - 0.5).abs() < 1.0e-3, "距離{距離}");
    assert_eq!(参照計算.点の位置一覧()[0], 位置を作る(0.0, 1.0, 0.0), "固定した点は動かない");
    assert!(参照計算.点と剛体の距離拘束の乗数一覧()[0].値() < 0.0, "伸びを縮める向きの乗数は負である");
}
