//! 判断6と判断19の検査: 一定の力を1刻み加えた剛体の運動量の変化が細分数に依らず H·F であること・衝撃を加えた剛体の運動量の変化が細分数に依らず P であること・
//! 点自由度と姿勢自由度が同じ拘束(点と剛体上の局所点の距離拘束)へ参加して距離が静止長へ収束することを固定する。

