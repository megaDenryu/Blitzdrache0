//! ねじり拘束の検査が共有する材料: 回転ベクトルと姿勢の生成と、局所x軸を共有する硬いねじり拘束の引数。

use blitz_math::{クォータニオン, ラジアン, ローカル, ワールド, 回転ベクトル, 方向};

use super::rotational_compliance::回転のコンプライアンス;
use super::twist_constraint::ねじり拘束の引数;
use crate::rigid_body::姿勢;

pub(super) fn 回転ベクトルを作る(x: f32, y: f32, z: f32) -> 回転ベクトル<ワールド> {
    回転ベクトル::成分から生成する(ラジアン::生成する(x), ラジアン::生成する(y), ラジアン::生成する(z))
}

pub(super) fn 姿勢を作る(回転: 回転ベクトル<ワールド>) -> 姿勢 {
    姿勢::回転から生成する(クォータニオン::<ローカル, ワールド>::回転ベクトルから生成する(
        回転,
    ))
}

pub(super) fn x軸のねじり拘束(静止の相対姿勢: クォータニオン<ローカル, ローカル>) -> ねじり拘束の引数 {
    ねじり拘束の引数::生成する(
        静止の相対姿勢,
        方向::生成する(1.0, 0.0, 0.0).unwrap_or_else(|誤り| panic!("x軸の方向を作れない: {誤り}")),
        回転のコンプライアンス::硬い(),
    )
}
