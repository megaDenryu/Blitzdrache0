//! ジャイロ項の扱い(判断8の数値方針)。正典は重心局所座標で後退オイラー法をニュートン法1回で解く陰的1段であり、本番の予測器はこれだけを持つ。
//! 陽的に足す形と省く形は判断8の反証(陽的は高速回転で発散し、省くと中間軸の反転が起きない)を固定する検査だけが使うため、検査のときだけ枝が在る。

use blitz_math::{ローカル, 慣性テンソル, 秒, 角速度};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ジャイロ項の扱い {
    陰的に一段解く,
    #[cfg(test)]
    陽的に足す,
    #[cfg(test)]
    省く,
}

impl ジャイロ項の扱い {
    // 局所座標の角速度 ω₀ を、この扱いでジャイロ項のぶんだけ進めた ω₁。回転力はこの後に陽的に足す(判断8の順)。
    pub(super) fn 局所の角速度を進める(
        &self,
        角速度: 角速度<ローカル>,
        慣性: &慣性テンソル<ローカル>,
        刻み幅: 秒,
    ) -> 角速度<ローカル> {
        match self {
            Self::陰的に一段解く => 慣性.ジャイロ項を陰的に一段解く(角速度, 刻み幅),
            #[cfg(test)]
            Self::陽的に足す => 慣性.ジャイロ項を陽的に一段足す(角速度, 刻み幅),
            #[cfg(test)]
            Self::省く => 角速度,
        }
    }
}
