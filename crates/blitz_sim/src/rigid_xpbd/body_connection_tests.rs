/// 質量1と3の剛体を重心で結ぶと、0.4メートルの隔たりを逆質量の比 3:1 で分けて 0.3 と 0.1 ずつ寄る。
#[test]
fn 重心へ作用する接続の補正は逆質量の比で分かれる() {
    let (軽い, 重い) = (主慣性123の質量特性(1.0), 主慣性123の質量特性(3.0));
    let 係数 = 接続拘束の引数::生成する(変位::零(), 変位::零(), コンプライアンス::硬い())
        .刻み幅で解く係数を導く(刻み幅::生成する(秒::生成する(1.0 / 60.0)).unwrap())
        .unwrap();
    let a = 姿勢自由度の参加者::動的(原点の配置(), &軽い);
    let b = 姿勢自由度の参加者::動的(配置::生成する(位置を作る(0.4, 0.0, 0.0), 姿勢::恒等()), &重い);
    let 接続拘束の一回の射影の結果::補正した { 補正a, 補正b, .. } = 係数.一回射影する(&a, &b, ラグランジュ乗数::零())
    else {
        panic!("射影が補正の枝を返さない");
    };
    assert!((補正a.並進().x().値() - 0.3).abs() < 1.0e-6, "{補正a:?}");
    assert!((補正b.並進().x().値() + 0.1).abs() < 1.0e-6, "{補正b:?}");
    assert!(補正a.回転().長さ().値() == 0.0 && 補正b.回転().長さ().値() == 0.0);
}

#[test]
fn 重心から離れた局所点どうしは反復で一致し両方の剛体が回る() {
    let mut 台帳 = 剛体の台帳::空();
    let 剛体a = 動的剛体を登録する(&mut 台帳, 原点の配置(), 主慣性123の質量特性(1.0));
    let 剛体b = 動的剛体を登録する(
        &mut 台帳,
        配置::生成する(位置を作る(2.5, 0.3, 0.0), 姿勢::恒等()),
        質量特性を作る(3.0, [3.0, 6.0, 9.0]),
    );
    let 引数 = 接続拘束の引数::生成する(
        局所の変位を作る(1.0, 0.0, 0.0),
        局所の変位を作る(-1.0, 0.0, 0.0),
        コンプライアンス::硬い(),
    );
    let 拘束 = vec![添字付き接続拘束 { 剛体a, 剛体b, 引数 }];
    let 参照計算 = 拘束を1刻み解いた台帳(
        台帳,
        剛体の拘束の一覧 {
            接続拘束: 拘束,
            ..剛体の拘束の一覧::空()
        },
    );
    let 点a = 剛体を参照する(&参照計算, 剛体a).配置().局所点の世界位置(局所の変位を作る(1.0, 0.0, 0.0));
    let 点b = 剛体を参照する(&参照計算, 剛体b).配置().局所点の世界位置(局所の変位を作る(-1.0, 0.0, 0.0));
    assert!((点a - 点b).長さ().値() < 1.0e-4, "点a{点a:?}と点b{点b:?}");
    let 回ったa = 剛体を参照する(&参照計算, 剛体a)
        .配置()
        .姿勢()
        .回転()
        .対数写像で回転ベクトルへ()
        .長さ()
        .値();
    let 回ったb = 剛体を参照する(&参照計算, 剛体b)
        .配置()
        .姿勢()
        .回転()
        .対数写像で回転ベクトルへ()
        .長さ()
        .値();
    assert!(回ったa > 0.0 && 回ったb > 0.0, "腕のある点への補正は両方を回す: {回ったa} {回ったb}");
    assert!(回ったa > 回ったb, "慣性の小さい剛体のほうが大きく回る: {回ったa} {回ったb}");
}
