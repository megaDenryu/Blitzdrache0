//! 姿勢自由度の補正: 1つの剛体が1回の射影で受ける並進の補正と回転の補正の組(判断9)。乗数の増分 Δλ から補正を作る式は、
//! 逆質量とワールドの逆慣性を所有する `姿勢自由度の参加者` のメソッドが持ち、この型は分配された結果と配置への適用だけを持つ。
//! 姿勢の正規化は姿勢の型が行う。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断9」。

use blitz_math::{ワールド, 回転ベクトル, 変位};

use crate::rigid_body::配置;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 姿勢自由度の補正 {
    並進: 変位<ワールド>,
    回転: 回転ベクトル<ワールド>,
}

impl 姿勢自由度の補正 {
    pub fn 零() -> Self {
        Self {
            並進: 変位::零(),
            回転: 回転ベクトル::零(),
        }
    }

    // 参加者が分配した並進と回転を組にする口。分配の式は参加者が持つため、この生成は検証を持たない。
    pub(super) fn 並進と回転から生成する(並進: 変位<ワールド>, 回転: 回転ベクトル<ワールド>) -> Self {
        Self { 並進, 回転 }
    }

    pub fn 並進(&self) -> 変位<ワールド> {
        self.並進
    }

    pub fn 回転(&self) -> 回転ベクトル<ワールド> {
        self.回転
    }

    /// 配置へ足した新しい配置。並進は重心へ、回転は姿勢の微小回転の更新へ渡す。
    pub fn 配置へ適用する(&self, 配置: &配置) -> 配置 {
        配置.並進で動かす(self.並進).微小回転で回す(self.回転)
    }
}
