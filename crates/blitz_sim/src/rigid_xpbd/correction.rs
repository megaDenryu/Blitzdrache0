//! 姿勢自由度の補正: Δλ を固定して受け、並進の補正と回転の補正へ分配する式(判断9)。CPUの参照計算の正典であり、GPUの写しは同じ符号・同じ演算順で書く。
//!   点に作用する拘束:   Δx = w · Δλ · n、Δq = (1/2)·[ I⁻¹ (r × (Δλ n)) ]_四元数 ⊗ q
//!   回転だけの拘束:     Δq = (1/2)·[ I⁻¹ (Δλ n) ]_四元数 ⊗ q
//! n はその剛体の勾配の向きであり、aからbへ向かう n に対して a の勾配は −n である(距離拘束の規約と同じ)。姿勢の正規化は姿勢の型が行う。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断9」。

use blitz_math::{ワールド, 回転ベクトル, 変位, 方向};

use super::participant::姿勢自由度の参加者;
use super::rotational_lagrange_multiplier::回転のラグランジュ乗数;
use crate::rigid_body::配置;
use crate::xpbd::ラグランジュ乗数;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 姿勢自由度の補正 {
    並進: 変位<ワールド>,
    回転: 回転ベクトル<ワールド>,
}

impl 姿勢自由度の補正 {
    pub fn 零() -> Self {
        Self {
            並進: 変位::零(),
            回転: 回転ベクトル::零(),
        }
    }

    /// 腕 r の点に勾配の向き n で乗数の増分 Δλ が作用したときの補正。Δx = w Δλ n、Δθ = I⁻¹ (r × (Δλ n))。
    pub fn 点に作用する乗数を分配する(
        参加者: &姿勢自由度の参加者,
        腕: 変位<ワールド>,
        勾配の向き: 方向<ワールド>,
        乗数の増分: ラグランジュ乗数,
    ) -> Self {
        Self {
            並進: 変位::方向へ進む(勾配の向き, 乗数の増分 * 参加者.逆質量()),
            回転: 参加者
                .ワールドの逆慣性()
                .腕に作用する乗数の回転(腕, 勾配の向き, 乗数の増分.キログラムメートル()),
        }
    }

    /// 軸 n のまわりの回転だけに乗数の増分 Δλ が作用したときの補正。Δθ = I⁻¹ (Δλ n)。
    pub fn 回転に作用する乗数を分配する(
        参加者: &姿勢自由度の参加者,
        勾配の向き: 方向<ワールド>,
        乗数の増分: 回転のラグランジュ乗数,
    ) -> Self {
        Self {
            並進: 変位::零(),
            回転: 参加者
                .ワールドの逆慣性()
                .向きに作用する回転の乗数の回転(勾配の向き, 乗数の増分.キログラム平方メートル()),
        }
    }

    pub fn 並進(&self) -> 変位<ワールド> {
        self.並進
    }

    pub fn 回転(&self) -> 回転ベクトル<ワールド> {
        self.回転
    }

    /// 配置へ足した新しい配置。並進は重心へ、回転は姿勢の微小回転の更新へ渡す。
    pub fn 配置へ適用する(&self, 配置: &配置) -> 配置 {
        配置.並進で動かす(self.並進).微小回転で回す(self.回転)
    }
}
