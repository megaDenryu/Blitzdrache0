//! 速度の再構成だけが読む仮の補正: 剛体の配置として確定してはならない補正(判断24)。
//! 中身は姿勢自由度の補正そのものであるが、配置へ適用する口をこの型が持たないため、呼び出し側は配置を書けない。
//! 素の姿勢自由度の補正で持つと、拘束の補正と同じ型になって取り違えても型が通り、閉じないと決めた変位を配置の側で
//! 閉じる経路(乗数を積まずに拘束を満たす経路)ができる。それを規律でなく型で止めるためにこの新型を置く。
//! 中身を読めるのは `前の状態::確定した配置と仮の補正から速度を再構成する` だけである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断24: 静止摩擦が閉じなかった接線変位は接触の履歴が持ち越し、位置からの速度の再構成から除く」

use super::correction::姿勢自由度の補正;

/// 速度の再構成だけが読む仮の補正。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 速度の再構成だけが読む仮の補正 {
    補正: 姿勢自由度の補正,
}

impl 速度の再構成だけが読む仮の補正 {
    /// 除くものが無い細分の補正。速度の再構成はこのとき判断9の従来の式をそのまま通る。
    pub fn 零() -> Self {
        Self {
            補正: 姿勢自由度の補正::零(),
        }
    }

    /// 残差の変化を打ち消す連立が求めた補正を包む。包んだ後は配置へ適用する道が無い。
    pub fn 残差の変化を打ち消す補正を包む(補正: 姿勢自由度の補正) -> Self {
        Self { 補正 }
    }

    /// 接触点集合ごとに求めた補正を1つの剛体について足し合わせる。
    pub fn 合わせる(&self, 相手: &Self) -> Self {
        Self {
            補正: self.補正.合わせる(&相手.補正),
        }
    }

    /// 零でなければ中身を返す。零の細分で速度の再構成が判断9の従来の式とビットで一致することを、この分岐が保つ
    /// (姿勢へ零の微小回転を掛ける経路は正規化を通るため、値がビットで一致する保証が無い)。
    pub(super) fn 零でなければ補正を読む(&self) -> Option<&姿勢自由度の補正> {
        (*self != Self::零()).then_some(&self.補正)
    }
}
