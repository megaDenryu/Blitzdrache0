//! 剛体の目標拘束を一回射影した結果。補正できた枝と、射影できない理由の枝を同じ型で返す(距離拘束と同じ様式)。
//! 理由の枝ではラグランジュ乗数は変わらず、呼び出し側は渡した値をそのまま次の反復へ持ち越す。

use super::correction::姿勢自由度の補正;
use crate::xpbd::ラグランジュ乗数;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 剛体の目標拘束の一回の射影の結果 {
    /// 補正を求めた。呼び出し側が予測の状態へ補正を適用し、更新後の乗数を次の反復へ渡す。
    補正した {
        補正: 姿勢自由度の補正,
        更新後のラグランジュ乗数: ラグランジュ乗数,
    },
    /// 剛体が静的または運動学的で、動かせない。
    剛体が動かせない,
    /// 剛体上の点が目標と一致していて、補正の向きが定まらない(拘束は満たされている)。
    目標と一致している,
}
