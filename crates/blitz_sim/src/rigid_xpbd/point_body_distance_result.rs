//! 点と剛体の距離拘束を一回射影した結果。理由の枝ではラグランジュ乗数は変わらず、呼び出し側は渡した値をそのまま次の反復へ持ち越す。

use blitz_math::{ワールド, 変位};

use super::correction::姿勢自由度の補正;
use crate::xpbd::ラグランジュ乗数;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 点と剛体の距離拘束の一回の射影の結果 {
    /// 補正を求めた。呼び出し側が点の位置へ`点の補正`を足し、剛体の予測の状態へ`剛体の補正`を適用し、更新後の乗数を次の反復へ渡す。
    補正した {
        点の補正: 変位<ワールド>,
        剛体の補正: 姿勢自由度の補正,
        更新後のラグランジュ乗数: ラグランジュ乗数,
    },
    /// 点の逆質量が0で剛体も動かせない。
    両方が動かせない,
    /// 点と剛体上の点が一致していて、補正の向きが定まらない。
    向きが定まらない,
}
