//! ねじり拘束を一回射影した結果。理由の枝ではラグランジュ乗数は変わらず、呼び出し側は渡した値をそのまま次の反復へ持ち越す。
//! 軸まわりの相対角が静止角に一致しているときも補正0の`補正した`を返す(拘束違反0は退化ではなく、勾配の向きは軸から常に定まる)。

use super::correction::姿勢自由度の補正;
use super::rotational_lagrange_multiplier::回転のラグランジュ乗数;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum ねじり拘束の一回の射影の結果 {
    /// 補正を求めた。呼び出し側が各剛体の予測の状態へ補正を適用し、更新後の乗数を次の反復へ渡す。
    補正した {
        補正a: 姿勢自由度の補正,
        補正b: 姿勢自由度の補正,
        更新後のラグランジュ乗数: 回転のラグランジュ乗数,
    },
    /// 両方の剛体が静的または運動学的で、どちらも動かせない。
    両方が動かせない,
}
