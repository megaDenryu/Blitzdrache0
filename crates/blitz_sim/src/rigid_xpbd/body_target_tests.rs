//! 判断10の剛体の目標拘束の検査。硬い接続で剛体上の点が目標へ一致し重心に作用すれば回転が生じないこと・柔らかい接続で解析解の定常の隔たり
//! C = α g ÷ w̃(重心へ作用する接続では w̃ = w であり α m g)を満たすことを固定する。柔らかい接続は準静的(毎刻みを静止から始める)に回し、減衰の無い振動が収まるのを待つ必要を無くす。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, 変位, 秒};

use super::body_target_constraint::剛体の目標拘束の引数;
use super::body_target_result::剛体の目標拘束の一回の射影の結果;
use super::participant::姿勢自由度の参加者;
use super::reference::{剛体の拘束の一覧, 添字付き剛体の目標拘束};
use super::reference_test_fixtures::{
    主慣性123の質量特性, 位置を作る, 剛体を参照する, 動的剛体を登録する, 原点の配置, 局所の変位を作る, 拘束を1刻み解いた台帳,
};
use crate::rigid_body::{剛体の台帳, 姿勢, 配置};
use crate::xpbd::{コンプライアンス, ラグランジュ乗数, 刻み幅};

#[test]
fn 硬い目標拘束は剛体上の点を目標へ一致させ重心へ作用すれば姿勢は変わらない() {
    let mut 台帳 = 剛体の台帳::空();
    let 離れた点 = 動的剛体を登録する(&mut 台帳, 原点の配置(), 主慣性123の質量特性(1.0));
    let 重心 = 動的剛体を登録する(&mut 台帳, 原点の配置(), 主慣性123の質量特性(1.0));
    let 拘束 = vec![
        添字付き剛体の目標拘束 {
            剛体: 離れた点,
            引数: 剛体の目標拘束の引数::生成する(局所の変位を作る(1.0, 0.0, 0.0), コンプライアンス::硬い()),
            目標: 位置を作る(1.0, 0.2, 0.0),
        },
        添字付き剛体の目標拘束 {
            剛体: 重心,
            引数: 剛体の目標拘束の引数::生成する(変位::零(), コンプライアンス::硬い()),
            目標: 位置を作る(0.3, 0.0, 0.0),
        },
    ];
    let 参照計算 = 拘束を1刻み解いた台帳(
        台帳,
        剛体の拘束の一覧 {
            剛体の目標拘束: 拘束,
            ..剛体の拘束の一覧::空()
        },
    );
    let 点の位置 = 剛体を参照する(&参照計算, 離れた点)
        .配置()
        .局所点の世界位置(局所の変位を作る(1.0, 0.0, 0.0));
    assert!((点の位置 - 位置を作る(1.0, 0.2, 0.0)).長さ().値() < 1.0e-4, "{点の位置:?}");
    let 重心の配置 = 剛体を参照する(&参照計算, 重心).配置();
    assert_eq!(*重心の配置.姿勢(), 姿勢::恒等(), "重心へ作用する拘束は回転を生まない");
    assert!((重心の配置.重心の位置() - 位置を作る(0.3, 0.0, 0.0)).長さ().値() < 1.0e-5);
}

// 準静的に重力で引かれる剛体を重心で柔らかく吊ると、定常の隔たりは C = α m g である(重心へ作用する接続なら w̃ = w)。
#[test]
fn 柔らかい目標拘束の定常の隔たりはコンプライアンスと重力と質量から解析的に決まる() {
    let (コンプライアンス, 重力, 質量, 刻み幅の秒) = (0.01f32, 9.8f32, 2.0f32, 1.0 / 60.0f32);
    let 質量特性 = 主慣性123の質量特性(質量);
    let 係数 = 剛体の目標拘束の引数::生成する(変位::零(), コンプライアンス::生成する(コンプライアンス).unwrap())
        .刻み幅で解く係数を導く(刻み幅::生成する(秒::生成する(刻み幅の秒)).unwrap())
        .unwrap();
    let 目標 = 位置を作る(0.0, 1.0, 0.0);
    let mut 配置: 配置 = 配置::生成する(目標, 姿勢::恒等());
    let 落ちる = 変位::成分から生成する(
        メートル::生成する(0.0),
        メートル::生成する(-重力 * 刻み幅の秒 * 刻み幅の秒),
        メートル::生成する(0.0),
    );
    for _ in 0..2000 {
        配置 = 配置.並進で動かす(落ちる);
        let mut 乗数 = ラグランジュ乗数::零();
        for _ in 0..8 {
            if let 剛体の目標拘束の一回の射影の結果::補正した {
                補正,
                更新後のラグランジュ乗数,
            } = 係数.一回射影する(&姿勢自由度の参加者::動的(配置, &質量特性), 目標, 乗数)
            {
                配置 = 補正.配置へ適用する(&配置);
                乗数 = 更新後のラグランジュ乗数;
            }
        }
    }
    let 隔たり = (目標 - 配置.重心の位置()).長さ().値();
    let 解析解 = コンプライアンス * 質量 * 重力;
    assert!((隔たり - 解析解).abs() < 1.0e-5, "隔たり{隔たり}に対して解析解{解析解}");
}
