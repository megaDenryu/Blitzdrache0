fn 主慣性を2倍にした質量特性(質量: f32) -> 質量特性 {
    let 慣性 = |値: f32| キログラム平方メートル::生成する(値);
    let 主慣性 = 主慣性::生成する(慣性(2.0), 慣性(4.0), 慣性(6.0));
    質量特性::生成する(
        blitz_math::キログラム::生成する(質量).unwrap(),
        変位::零(),
        主慣性と主軸::生成する(主慣性, クォータニオン::軸が一致する回転()).unwrap(),
    )
    .unwrap()
}

fn 世界の変位を作る(x: f32, y: f32, z: f32) -> 変位<ワールド> {
    変位::成分から生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

#[test]
fn 重心へ作用する乗数は回転を生まず補正は逆質量と逆慣性に比例する() {
    let 上 = 方向::生成する(0.0, 1.0, 0.0).unwrap();
    let 乗数 = ラグランジュ乗数::長さを逆質量で割って生成する(
        メートル::生成する(0.5),
        blitz_math::逆キログラム::生成する(1.0).unwrap(),
    );
    let 基準 = 姿勢自由度の参加者::動的(原点の配置(), &主慣性123の質量特性(1.0));
    let 重心へ = 基準.点に作用する乗数を補正へ分配する(世界の変位を作る(0.0, 0.0, 0.0), 上, 乗数);
    assert!(重心へ.回転().長さ().値() == 0.0 && (重心へ.並進().y().値() - 0.5).abs() < 1.0e-6);
    let 腕 = 世界の変位を作る(1.0, 0.0, 0.0);
    let 離れた点へ = 基準.点に作用する乗数を補正へ分配する(腕, 上, 乗数);
    let 質量2倍 = 姿勢自由度の参加者::動的(原点の配置(), &主慣性123の質量特性(2.0)).点に作用する乗数を補正へ分配する(腕, 上, 乗数);
    let 慣性2倍 =
        姿勢自由度の参加者::動的(原点の配置(), &主慣性を2倍にした質量特性(1.0)).点に作用する乗数を補正へ分配する(腕, 上, 乗数);
    assert!((質量2倍.並進().y().値() * 2.0 - 離れた点へ.並進().y().値()).abs() < 1.0e-6);
    assert_eq!(質量2倍.回転(), 離れた点へ.回転());
    assert!((慣性2倍.回転().z().値() * 2.0 - 離れた点へ.回転().z().値()).abs() < 1.0e-6);
    assert_eq!(慣性2倍.並進(), 離れた点へ.並進());
}

// 解析解: 腕 r = (1, 0, 0)、目標が点から y に d だけ離れているとき n = (0, 1, 0)、r × n = (0, 0, 1)、w̃ = w + 1 ÷ J₃、
// Δλ = −d ÷ w̃、Δx = (0, w d ÷ w̃, 0)、Δθ = (0, 0, d ÷ (w̃ J₃)) である。
#[test]
fn 世界固定点の目標拘束の一回の射影は解析解と一致する() {
    let (d, 質量, 第三主慣性) = (0.1f32, 2.0f32, 3.0f32);
    let 質量特性 = 主慣性123の質量特性(質量);
    let 参加者 = 姿勢自由度の参加者::動的(原点の配置(), &質量特性);
    let 係数 = 剛体の目標拘束の引数::生成する(局所の変位を作る(1.0, 0.0, 0.0), コンプライアンス::硬い())
        .刻み幅で解く係数を導く(刻み幅::生成する(秒::生成する(1.0 / 60.0)).unwrap())
        .unwrap();
    let 剛体の目標拘束の一回の射影の結果::補正した {
        補正,
        更新後のラグランジュ乗数,
    } = 係数.一回射影する(&参加者, 位置を作る(1.0, d, 0.0), ラグランジュ乗数::零())
    else {
        panic!("射影が補正の枝を返さない");
    };
    let (w, 有効逆質量) = (1.0 / 質量, 1.0 / 質量 + 1.0 / 第三主慣性);
    assert!(
        (更新後のラグランジュ乗数.値() + d / 有効逆質量).abs() < 1.0e-6,
        "乗数{}",
        更新後のラグランジュ乗数.値()
    );
    assert!((補正.並進().y().値() - w * d / 有効逆質量).abs() < 1.0e-6, "並進{:?}", 補正.並進());
    assert!(
        (補正.回転().z().値() - d / (有効逆質量 * 第三主慣性)).abs() < 1.0e-6,
        "回転{:?}",
        補正.回転()
    );
    assert!(補正.並進().x().値().abs() < 1.0e-7 && 補正.回転().x().値().abs() < 1.0e-7);
}

#[test]
fn 微小な回転から再構成した角速度は解析値と相対1e_4以内で一致する() {
    let 刻み幅 = 刻み幅::生成する(秒::生成する(1.0 / 480.0)).unwrap();
    let 前 = 前の状態::配置から保存する(&原点の配置());
    let 回転 = 回転ベクトル::成分から生成する(ラジアン::生成する(0.002), ラジアン::生成する(-0.001), ラジアン::生成する(0.0005));
    let 確定: 配置 = 原点の配置().微小回転で回す(回転);
    let 角速度 = 前.確定した配置から速度を再構成する(&確定, 刻み幅).角速度();
    let 解析値 = 回転 / 刻み幅.秒();
    assert!(
        (角速度 - 解析値).長さ().値() / 解析値.長さ().値() < 1.0e-4,
        "角速度{角速度:?}に対して解析値{解析値:?}"
    );
}
