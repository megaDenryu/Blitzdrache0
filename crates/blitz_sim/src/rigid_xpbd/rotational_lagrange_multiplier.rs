//! 回転だけに作用する拘束(ねじり・軸まわりの角度)のラグランジュ乗数。単位はキログラム平方メートルであり、逆慣性(毎キログラム平方メートル)を掛けると角(ラジアン)になる。
//! 位置の拘束の乗数(キログラムメートル)と次元が違うため別の型で持つ。点自由度の曲げ拘束の乗数(`曲げのラグランジュ乗数`)と同じ次元だが、
//! 姿勢自由度の逆慣性テンソルへ写す口を持つのがこちらである。寿命は呼び出し側が持ち、細分の開始で`零()`から始める(判断5)。

use std::ops::{Add, Mul};

use blitz_math::{キログラム平方メートル, ラジアン, 逆キログラム平方メートル};

#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 回転のラグランジュ乗数(f32);

impl 回転のラグランジュ乗数 {
    pub fn 零() -> Self {
        Self(0.0)
    }

    /// 角を逆慣性で割った量。Δλ = (−C − α̃λ) ÷ (有効逆慣性 + α̃) がこの形である。
    /// 前提: 逆慣性は正である(有効逆慣性が0の拘束は射影の前に退化として除かれる)。
    pub fn 角を逆慣性で割って生成する(角: ラジアン, 逆慣性: 逆キログラム平方メートル) -> Self {
        Self(角.値() / 逆慣性.値())
    }

    /// 逆慣性テンソルへ渡す大きさ。
    pub fn キログラム平方メートル(&self) -> キログラム平方メートル {
        キログラム平方メートル::生成する(self.0)
    }

    /// 境界向けの生値取り出し。ドメインAPI内部では使わない。
    pub fn 値(&self) -> f32 {
        self.0
    }
}

impl Add for 回転のラグランジュ乗数 {
    type Output = Self;
    fn add(self, 右辺: Self) -> Self {
        Self(self.0 + 右辺.0)
    }
}

/// 次元の合成: 乗数 × 逆慣性 = 角。反復の式の α̃λ の項である。
impl Mul<逆キログラム平方メートル> for 回転のラグランジュ乗数 {
    type Output = ラジアン;
    fn mul(self, 逆慣性: 逆キログラム平方メートル) -> ラジアン {
        ラジアン::生成する(self.0 * 逆慣性.値())
    }
}
