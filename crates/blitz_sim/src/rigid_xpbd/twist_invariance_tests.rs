//! 判断10のねじり拘束の座標系の不変の検査。2剛体を同じ回転で回した配置で一回の射影の乗数と補正(全体の回転を戻した値)が変わらないことを固定する。
//! 反証: 拘束違反をワールドの回転ベクトルと局所の軸で内積すると、全体を回した配置で結果が変わる。

#![allow(clippy::unwrap_used)]

use blitz_math::{クォータニオン, ワールド, 回転ベクトル, 秒};

use super::participant::姿勢自由度の参加者;
use super::reference_test_fixtures::{主慣性123の質量特性, 位置を作る};
use super::rotational_lagrange_multiplier::回転のラグランジュ乗数;
use super::twist_result::ねじり拘束の一回の射影の結果;
use super::twist_test_fixtures::{x軸のねじり拘束, 回転ベクトルを作る, 姿勢を作る};
use crate::rigid_body::{姿勢, 配置};
use crate::xpbd::刻み幅;

/// 全体の回転で回した2剛体へ一回射影し、乗数と、全体の回転を戻した2つの回転の補正を返す。
fn 全体を回して射影する(
    全体の回転: 回転ベクトル<ワールド>,
) -> (回転のラグランジュ乗数, 回転ベクトル<ワールド>, 回転ベクトル<ワールド>) {
    let 係数 = x軸のねじり拘束(クォータニオン::恒等())
        .刻み幅で解く係数を導く(刻み幅::生成する(秒::生成する(1.0 / 60.0)).unwrap())
        .unwrap();
    let 質量特性 = 主慣性123の質量特性(1.0);
    let 全体 = クォータニオン::<ワールド, ワールド>::回転ベクトルから生成する(全体の回転);
    let a = 姿勢::回転から生成する(姿勢::恒等().回転().続けて回す(&全体));
    let b = 姿勢::回転から生成する(姿勢を作る(回転ベクトルを作る(0.25, 0.1, -0.05)).回転().続けて回す(&全体));
    let 結果 = 係数.一回射影する(
        &姿勢自由度の参加者::動的(配置::生成する(位置を作る(0.0, 0.0, 0.0), a), &質量特性),
        &姿勢自由度の参加者::動的(配置::生成する(位置を作る(1.0, 0.0, 0.0), b), &質量特性),
        回転のラグランジュ乗数::零(),
    );
    let ねじり拘束の一回の射影の結果::補正した {
        補正a,
        補正b,
        更新後のラグランジュ乗数,
    } = 結果
    else {
        panic!("射影が補正の枝を返さない");
    };
    (
        更新後のラグランジュ乗数,
        全体.逆回転().回転ベクトルを回す(補正a.回転()),
        全体.逆回転().回転ベクトルを回す(補正b.回転()),
    )
}

#[test]
fn ねじり拘束の一回の射影は2剛体を同じ回転で回した配置で不変である() {
    let 基準 = 全体を回して射影する(回転ベクトルを作る(0.0, 0.0, 0.0));
    let 回した = 全体を回して射影する(回転ベクトルを作る(0.7, -1.1, 0.4));
    let 乗数の許容 = 1.0e-5 * 基準.0.値().abs().max(1.0);
    assert!((基準.0.値() - 回した.0.値()).abs() < 乗数の許容, "乗数{:?}と{:?}", 基準.0, 回した.0);
    assert!((基準.1 - 回した.1).長さ().値() < 1.0e-5, "補正a{:?}と{:?}", 基準.1, 回した.1);
    assert!((基準.2 - 回した.2).長さ().値() < 1.0e-5, "補正b{:?}と{:?}", 基準.2, 回した.2);
    assert!(基準.0.値() != 0.0 && 基準.1.長さ().値() > 0.0, "題材の拘束違反は零でない");
}
