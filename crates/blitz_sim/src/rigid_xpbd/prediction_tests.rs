//! 判断8の検査4つ。主慣性(1, 2, 3)・細分の刻み幅1/480秒・外力なしの自由回転で、(1)角運動量の大きさが初期値の(1 + ε)を越えないこと、
//! (2)刻み幅を半分にすると角運動量の減少量が減ること、(3)中間軸の摂動が有限の細分数で反転し省いた反証では反転しないこと、
//! (4)陽的なジャイロ項が100細分以内に発散し陰的1段では(1 + ε)を越えないこと、を固定する。角速度は再構成の結果を次の細分が読む(判断9)。
//! 反復の中の角速度の読み戻しは`_doc/計測/剛体の姿勢自由度_2026-09-02.md`に記録する。

#![allow(clippy::unwrap_used)]

use super::gyroscopic_treatment::ジャイロ項の扱い;
