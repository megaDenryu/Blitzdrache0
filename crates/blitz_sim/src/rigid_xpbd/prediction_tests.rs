// 角運動量の大きさが初期値からどれだけ増えてよいか。判断8の暫定値1e-2であり、実測は600細分で減少側に4.0パーセントであり増加は無いため置き直していない。
const 角運動量の増加の許容: f32 = 1.0e-2;

fn 剛体(参照計算: &剛体の参照計算) -> &剛体 {
    &参照計算.台帳().剛体一覧()[0]
}

fn 細分を進める(参照計算: &mut 剛体の参照計算, 細分の数: u32) {
    参照計算.一刻み進める(細分数::生成する(細分の数).unwrap()).unwrap();
}

#[test]
fn 主軸の外の自由回転を600細分進めても角運動量の大きさは初期値の一定倍を越えない() {
    let mut 参照計算 = 自由回転の参照計算(角速度を作る(3.0, 7.0, 5.0), 判断8の刻み幅の秒, ジャイロ項の扱い::陰的に一段解く);
    let 初期値 = 角運動量の大きさ(剛体(&参照計算));
    細分を進める(&mut 参照計算, 600);
    let 比 = 角運動量の大きさ(剛体(&参照計算)) / 初期値;
    assert!(比.is_finite() && 比 <= 1.0 + 角運動量の増加の許容, "600細分後の角運動量の比{比}");
    assert!(剛体(&参照計算).配置().姿勢().長さの1からのずれ() < 1.0e-5);
}

#[test]
fn 刻み幅を半分にすると同じ実時間の角運動量の減少量が減る() {
    let 減少量 = |刻み幅の秒: f32, 細分の数: u32| {
        let mut 参照計算 = 自由回転の参照計算(角速度を作る(3.0, 7.0, 5.0), 刻み幅の秒, ジャイロ項の扱い::陰的に一段解く);
        let 初期値 = 角運動量の大きさ(剛体(&参照計算));
        細分を進める(&mut 参照計算, 細分の数);
        初期値 - 角運動量の大きさ(剛体(&参照計算))
    };
    let (粗い, 細かい) = (減少量(判断8の刻み幅の秒, 600), 減少量(判断8の刻み幅の秒 / 2.0, 1200));
    assert!(粗い > 0.0, "陰的1段は散逸する: {粗い}");
    assert!(細かい < 粗い, "刻み幅1/480秒の減少量{粗い}に対して1/960秒の減少量{細かい}");
}

// 反証: ジャイロ項を省くと角速度がワールドで一定のまま体が回り、中間軸の成分は符号を変えない。
#[test]
fn 中間軸の摂動つきの回転は有限の細分数で反転しジャイロ項を省くと反転しない() {
    let 反転するまでの細分数 = |扱い: ジャイロ項の扱い| {
        let mut 参照計算 = 自由回転の参照計算(角速度を作る(0.01, 10.0, 0.0), 判断8の刻み幅の秒, 扱い);
        (1..=4000u32).find(|_| {
            細分を進める(&mut 参照計算, 1);
            局所の中間軸の角速度(剛体(&参照計算)) < 0.0
        })
    };
    let 陰的 = 反転するまでの細分数(ジャイロ項の扱い::陰的に一段解く);
    assert!(陰的.is_some(), "陰的1段では中間軸の成分が反転する");
    assert_eq!(反転するまでの細分数(ジャイロ項の扱い::省く), None, "反証: 省くと反転しない");
}

// 反証: 陽的に足すと主軸の外の高速回転が発散する。各細分で検査し、最初に2倍を越えるか非有限になった時点で反証の成立とする。
// 予測の角速度をそのまま次の細分へ渡して回す(判断8の数値方針だけを見る)。速度の再構成を通した全体の経路では、微小回転として読む
// 再構成が角速度を 2 ÷ h に抑えるため陽的な更新の発散が角運動量の比に現れない(`_doc/計測/剛体の姿勢自由度_2026-09-02.md`)。
#[test]
fn 陽的なジャイロ項は高速回転で100細分以内に発散し陰的1段は発散しない() {
    let 初期値 = 角運動量の大きさ(剛体(&自由回転の参照計算(
        角速度を作る(0.0, 200.0, 150.0),
        判断8の刻み幅の秒,
        ジャイロ項の扱い::陰的に一段解く,
    )));
    let 陽的 = 予測の角速度で回した角運動量の比(ジャイロ項の扱い::陽的に足す, 初期値);
    assert!(
        陽的.iter().any(|比| !比.is_finite() || *比 > 2.0),
        "陽的な更新は100細分以内に発散する: {陽的:?}"
    );
    let 陰的 = 予測の角速度で回した角運動量の比(ジャイロ項の扱い::陰的に一段解く, 初期値);
    assert!(
        陰的.iter().all(|比| 比.is_finite() && *比 <= 1.0 + 角運動量の増加の許容),
        "陰的1段の比{陰的:?}"
    );
}

// 主慣性(1, 2, 3)・初期角速度(0, 200, 150)・刻み幅1/480秒で予測だけを100細分回し、細分ごとの角運動量の大きさの初期値に対する比を返す。
pub(super) fn 予測の角速度で回した角運動量の比(扱い: ジャイロ項の扱い, 初期値: f32) -> Vec<f32> {
    let 予測器 = 予測器を作る(判断8の刻み幅の秒, 0.0, 扱い);
    let 質量特性 = 主慣性123の質量特性(1.0);
    let (mut 配置, mut 運動状態) = (原点の配置(), 運動状態::生成する(速度::零(), 角速度を作る(0.0, 200.0, 150.0)));
    (0..100)
        .map(|_| {
            let (_, 予測, 予測の運動状態) = 予測器.動的剛体を予測する(&配置, &運動状態, &質量特性, &一刻みの入力::無し());
            (配置, 運動状態) = (*予測.配置(), 予測の運動状態);
            let 局所の角速度 = 配置.姿勢().逆回転().角速度を回す(運動状態.角速度());
            質量特性
                .主慣性と主軸()
                .局所の慣性テンソル()
                .角速度を角運動量へ写す(局所の角速度)
                .長さ()
                .値()
                / 初期値
        })
        .collect()
}
