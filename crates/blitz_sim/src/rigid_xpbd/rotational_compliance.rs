//! 回転だけに作用する拘束(ねじり・軸まわりの角度)の柔らかさ。単位は毎ニュートンメートル(秒の2乗毎キログラム平方メートル)であり、0で硬い拘束、正で有限の柔らかさになる。
//! 位置の拘束のコンプライアンス(メートル毎ニュートン)と次元が違うため別の型で持ち、伸びの物性を倍率で流用して回転を表す経路を型で閉じる。
//! 刻み依存量 α̃ = コンプライアンス ÷ 刻み幅² は逆慣性(毎キログラム平方メートル)の次元を持ち、回転だけの一般化逆質量へそのまま足せる。

use blitz_math::逆キログラム平方メートル;
use thiserror::Error;

use crate::xpbd::刻み幅;

#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 回転のコンプライアンス(f32);

impl 回転のコンプライアンス {
    /// 負と非有限を型付きエラーで拒む。0は硬い拘束として許す。
    pub fn 生成する(値: f32) -> Result<Self, 回転のコンプライアンスエラー> {
        if !値.is_finite() {
            return Err(回転のコンプライアンスエラー::非有限値 { 値 });
        }
        if 値 < 0.0 {
            return Err(回転のコンプライアンスエラー::負の値 { 値 });
        }
        Ok(Self(値))
    }

    pub fn 硬い() -> Self {
        Self(0.0)
    }

    /// 細分の開始時に1度だけ導く刻み依存量。単精度の表現範囲を超える組み合わせは型付きエラーで拒む。
    pub fn 刻み依存量(&self, 刻み幅: 刻み幅) -> Result<逆キログラム平方メートル, 回転のコンプライアンスエラー> {
        let 刻み = 刻み幅.秒().値();
        let 値 = self.0 / (刻み * 刻み);
        逆キログラム平方メートル::生成する(値).map_err(|_| 回転のコンプライアンスエラー::刻み依存量が範囲を外れた { 値 })
    }

    /// 境界向けの生値取り出し。ドメインAPI内部では使わない。
    pub fn 値(&self) -> f32 {
        self.0
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 回転のコンプライアンスエラー {
    #[error("回転のコンプライアンスは有限値でなければならない(指定値: {値})")]
    非有限値 { 値: f32 },
    #[error("回転のコンプライアンスは0以上でなければならない(指定値: {値})")]
    負の値 { 値: f32 },
    #[error("回転のコンプライアンスを刻み幅の2乗で割った量が単精度の範囲を外れた(結果: {値})")]
    刻み依存量が範囲を外れた { 値: f32 },
}
