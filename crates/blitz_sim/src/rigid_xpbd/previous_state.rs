//! 前の状態: 細分の予測の直前に保存した重心の位置と姿勢(判断8)。反復を終えた確定の配置との差から速度と角速度を再構成する(判断9)。
//! 予測の状態と別の型にするのは、拘束の補正が予測の型だけに掛かり、前の状態が反復の間に書き換わらないことを型で保つためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断8」「判断9」。

use blitz_math::{ワールド, 位置};

use super::correction::姿勢自由度の補正;
use crate::rigid_body::{姿勢, 運動状態, 配置};
use crate::xpbd::刻み幅;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 前の状態 {
    重心の位置: 位置<ワールド>,
    姿勢: 姿勢,
}

impl 前の状態 {
    pub fn 配置から保存する(配置: &配置) -> Self {
        Self {
            重心の位置: 配置.重心の位置(),
            姿勢: *配置.姿勢(),
        }
    }

    pub fn 重心の位置(&self) -> 位置<ワールド> {
        self.重心の位置
    }

    pub fn 姿勢(&self) -> &姿勢 {
        &self.姿勢
    }

    /// 保存した重心の位置と姿勢を配置として読む。細分の予測の前の配置を要る工程がここから作る
    /// (接触が始まった細分の静止摩擦の錨は、予測の後でなくこの配置の接触点に置く)。
    pub fn 保存した配置(&self) -> 配置 {
        配置::生成する(self.重心の位置, self.姿勢)
    }

    /// 確定した配置へ「残差の変化を打ち消す仮の補正」を足した仮の配置から速度と角速度を作る(判断24)。
    /// 仮の補正は剛体の配置として確定せず、この再構成だけが読む。解けずに残した接線変位がその細分で動いた量を
    /// 速度へ運ばせないためである。補正が零なら下の従来の式と1ビットも変わらない。
    pub fn 確定した配置と仮の補正から速度を再構成する(
        &self,
        確定: &配置,
        残差の変化を打ち消す仮の補正: &姿勢自由度の補正,
        刻み幅: 刻み幅,
    ) -> 運動状態 {
        self.確定した配置から速度を再構成する(&残差の変化を打ち消す仮の補正.配置へ適用する(確定), 刻み幅)
    }

    /// v = (x − x_前) ÷ h、ω = 2·vec(q ⊗ q_前⁻¹) ÷ h。反復を終えた確定の配置から速度と角速度を作る(判断9)。
    pub fn 確定した配置から速度を再構成する(&self, 確定: &配置, 刻み幅: 刻み幅) -> 運動状態 {
        let h = 刻み幅.秒();
        運動状態::生成する(
            (確定.重心の位置() - self.重心の位置) / h,
            確定.姿勢().前の姿勢からの微小回転(&self.姿勢) / h,
        )
    }
}
