//! 前の状態: 細分の予測の直前に保存した重心の位置と姿勢(判断8)。反復を終えた確定の配置との差から速度と角速度を再構成する(判断9)。
//! 予測の状態と別の型にするのは、拘束の補正が予測の型だけに掛かり、前の状態が反復の間に書き換わらないことを型で保つためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断8」「判断9」。

use blitz_math::{ワールド, 位置};

use super::velocity_only_correction::速度の再構成だけが読む仮の補正;
use crate::rigid_body::{姿勢, 運動状態, 配置};
use crate::xpbd::刻み幅;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 前の状態 {
    重心の位置: 位置<ワールド>,
    姿勢: 姿勢,
}

impl 前の状態 {
    pub fn 配置から保存する(配置: &配置) -> Self {
        Self {
            重心の位置: 配置.重心の位置(),
            姿勢: *配置.姿勢(),
        }
    }

    pub fn 重心の位置(&self) -> 位置<ワールド> {
        self.重心の位置
    }

    pub fn 姿勢(&self) -> &姿勢 {
        &self.姿勢
    }

    /// 保存した重心の位置と姿勢を配置として読む。細分の予測の前の配置を要る工程がここから作る
    /// (接触が始まった細分の静止摩擦の錨は、予測の後でなくこの配置の接触点に置く)。
    pub fn 保存した配置(&self) -> 配置 {
        配置::生成する(self.重心の位置, self.姿勢)
    }

    /// 位置から再構成した速度から、「残差の変化を打ち消す仮の補正」を速度の単位へ直した量を引く(判断24)。
    /// 仮の補正を配置へ足してから割るのではなく、速度の領域で引く。世界の原点から離れた接触では単精度の位置の
    /// 表現の刻みが仮の補正より大きく、足しても位置のビットが1つも変わらないためである(坂の場面では接触が
    /// 原点から20.5メートルにあり、刻みは1.9e-6メートル、仮の補正はその刻みの1個分と半分である)。
    /// 速度は0.001メートル毎秒の桁であり、同じ量を刻み幅で割った値は丸めに負けない。
    /// 補正が零なら引く量が零であり、下の従来の式と1ビットも変わらない。
    pub fn 確定した配置と仮の補正から速度を再構成する(
        &self,
        確定: &配置,
        残差の変化を打ち消す仮の補正: &速度の再構成だけが読む仮の補正,
        刻み幅: 刻み幅,
    ) -> 運動状態 {
        let 位置から再構成した = self.確定した配置から速度を再構成する(確定, 刻み幅);
        let Some(補正) = 残差の変化を打ち消す仮の補正.零でなければ補正を読む() else {
            return 位置から再構成した;
        };
        let h = 刻み幅.秒();
        運動状態::生成する(
            位置から再構成した.並進速度() + 補正.並進() / h,
            位置から再構成した.角速度() + 補正.回転() / h,
        )
    }

    /// v = (x − x_前) ÷ h、ω = 2·vec(q ⊗ q_前⁻¹) ÷ h。反復を終えた確定の配置から速度と角速度を作る(判断9)。
    pub fn 確定した配置から速度を再構成する(&self, 確定: &配置, 刻み幅: 刻み幅) -> 運動状態 {
        let h = 刻み幅.秒();
        運動状態::生成する(
            (確定.重心の位置() - self.重心の位置) / h,
            確定.姿勢().前の姿勢からの微小回転(&self.姿勢) / h,
        )
    }
}
