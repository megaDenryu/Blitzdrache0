//! 参照計算の一刻み(判断19の細分の工程のうち、接触と島と休止を除いた部分列)。
//!   工程2: 動的剛体ごとに蓄積器を取り出し、力と回転力を一刻みの入力として保持し、衝撃と回転衝撃を最初の細分の前に1度だけ速度へ足す
//!   細分 × n: 予測(前の状態の保存を含む)→乗数の零化→反復 × 反復回数(目標→接続→ねじり→点との距離)→速度と角速度の再構成→台帳へ書き戻す

use super::substep_body::細分の中の剛体;
use super::剛体の参照計算;
use crate::rigid_body::{一刻みの入力, 剛体の識別子, 運動種別};
use crate::rigid_xpbd::error::剛体の参照計算エラー;
use crate::rigid_xpbd::participant::姿勢自由度の参加者;
use crate::rigid_xpbd::substep_count::細分数;

impl 剛体の参照計算 {
    /// 基本刻み1本を細分数ぶんの細分で進める。
    pub fn 一刻み進める(&mut self, 細分数: 細分数) -> Result<(), 剛体の参照計算エラー> {
        let mut 入力一覧 = vec![一刻みの入力::無し(); self.台帳.剛体一覧().len()];
        let 動的な識別子一覧: Vec<剛体の識別子> = self
            .台帳
            .剛体一覧()
            .iter()
            .filter(|剛体| matches!(剛体.運動種別(), 運動種別::動的 { .. }))
            .map(|剛体| 剛体.識別子())
            .collect();
        for 識別子 in 動的な識別子一覧 {
            let (入力, 衝撃) = self.台帳.作用を取り出す(識別子)?;
            入力一覧[識別子.配列添字()] = 入力;
            let 剛体 = self.台帳.参照する(識別子)?;
            let 参加者 = 姿勢自由度の参加者::動的(*剛体.配置(), 剛体.質量特性());
            let 速度 = 衝撃.運動状態へ適用する(剛体.速度()?, 参加者.逆質量(), 参加者.ワールドの逆慣性());
            self.台帳.配置と速度を書き換える(識別子, *剛体.配置(), 速度)?;
        }
        for _ in 0..細分数.値() {
            self.一細分進める(&入力一覧)?;
        }
        Ok(())
    }

    fn 一細分進める(&mut self, 入力一覧: &[一刻みの入力]) -> Result<(), 剛体の参照計算エラー> {
        let mut 剛体一覧 = self.予測する(入力一覧)?;
        let 重力の変位 = self.予測器.重力の一刻みの変位();
        for 点 in &mut self.点一覧 {
            点.予測する(重力の変位);
        }
        self.剛体の目標拘束.乗数を零にする();
        self.接続拘束.乗数を零にする();
        self.ねじり拘束.乗数を零にする();
        self.点と剛体の距離拘束.乗数を零にする();
        for _ in 0..self.反復回数 {
            self.剛体の目標拘束.一回反復する(&mut 剛体一覧);
            self.接続拘束.一回反復する(&mut 剛体一覧);
            self.ねじり拘束.一回反復する(&mut 剛体一覧);
            self.点と剛体の距離拘束.一回反復する(&mut 剛体一覧, &mut self.点一覧);
        }
        self.確定して書き戻す(剛体一覧)
    }

    fn 予測する(&self, 入力一覧: &[一刻みの入力]) -> Result<Vec<細分の中の剛体>, 剛体の参照計算エラー> {
        let mut 剛体一覧 = Vec::with_capacity(self.台帳.剛体一覧().len());
        for 剛体 in self.台帳.剛体一覧() {
            剛体一覧.push(match 剛体.運動種別() {
                運動種別::動的 { 運動状態, .. } => {
                    let (前の状態, 予測, _) =
                        self.予測器
                            .動的剛体を予測する(剛体.配置(), 運動状態, 剛体.質量特性(), &入力一覧[剛体.識別子().配列添字()]);
                    細分の中の剛体::動的 {
                        前の状態,
                        予測,
                        質量特性: *剛体.質量特性(),
                    }
                }
                運動種別::静的 | 運動種別::運動学的 { .. } => 細分の中の剛体::動かせない { 配置: *剛体.配置() },
            });
        }
        Ok(剛体一覧)
    }

    fn 確定して書き戻す(&mut self, 剛体一覧: Vec<細分の中の剛体>) -> Result<(), 剛体の参照計算エラー> {
        let 刻み幅 = self.予測器.刻み幅();
        for (識別子, 細分の剛体) in self.台帳.識別子一覧().collect::<Vec<_>>().into_iter().zip(剛体一覧) {
            if let 細分の中の剛体::動的 { 前の状態, 予測, .. } = 細分の剛体 {
                let 速度 = 前の状態.確定した配置から速度を再構成する(予測.配置(), 刻み幅);
                self.台帳.配置と速度を書き換える(識別子, *予測.配置(), 速度)?;
            }
        }
        Ok(())
    }
}
