//! 細分の中の剛体: 参照計算が細分1本の間だけ持つ剛体の作業域。動かせない剛体は配置だけを、動的剛体は前の状態と予測の状態と質量特性を持つ。
//! 拘束の反復はここから参加者を作り、補正を予測の状態へ適用する(判断8の「補正は予測の型だけに掛かる」)。

use super::super::correction::姿勢自由度の補正;
use super::super::participant::姿勢自由度の参加者;
use super::super::predicted_state::予測の状態;
use super::super::previous_state::前の状態;
use crate::rigid_body::{質量特性, 配置};

pub(super) enum 細分の中の剛体 {
    動かせない {
        配置: 配置,
    },
    動的 {
        前の状態: 前の状態,
        予測: 予測の状態,
        質量特性: 質量特性,
    },
}

impl 細分の中の剛体 {
    // 拘束の射影が読む参加者。動的剛体はワールドの逆慣性を現在の予測の姿勢で組む。
    pub(super) fn 参加者(&self) -> 姿勢自由度の参加者 {
        match self {
            Self::動かせない { 配置 } => 姿勢自由度の参加者::動かせない(*配置),
            Self::動的 { 予測, 質量特性, .. } => 姿勢自由度の参加者::動的(*予測.配置(), 質量特性),
        }
    }

    // 補正を予測の状態へ足す。動かせない剛体は変えない(補正は零のはずであり、零でなくても受け付けない)。
    pub(super) fn 補正を適用する(&mut self, 補正: &姿勢自由度の補正) {
        if let Self::動的 { 予測, .. } = self {
            *予測 = 予測.補正を適用する(補正);
        }
    }
}
