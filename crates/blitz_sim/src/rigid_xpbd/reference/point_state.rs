//! 参照計算が持つ点自由度の状態。位置と前の位置と逆質量であり、速度は位置の差で表す(ベルレ形。`拘束グラフの参照計算`と同じ)。
//! 剛体と点の距離拘束が点の側の参加者をここから作る。

use blitz_math::{ワールド, 位置, 変位, 逆キログラム};

use crate::constraint_graph::点自由度の初期状態;
use crate::xpbd::距離拘束の参加点;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 点の細分の状態 {
    位置: 位置<ワールド>,
    前の位置: 位置<ワールド>,
    逆質量: 逆キログラム,
}

impl 点の細分の状態 {
    pub(super) fn 初期状態から生成する(初期状態: &点自由度の初期状態) -> Self {
        Self {
            位置: 初期状態.位置,
            前の位置: 初期状態.位置,
            逆質量: 初期状態.逆質量,
        }
    }

    pub(super) fn 位置(&self) -> 位置<ワールド> {
        self.位置
    }

    pub(super) fn 参加点(&self) -> 距離拘束の参加点 {
        距離拘束の参加点::生成する(self.位置, self.逆質量)
    }

    /// 前の位置との差(速度)と重力の変位を足して予測する。固定した点は動かさない。
    pub(super) fn 予測する(&mut self, 重力の変位: 変位<ワールド>) {
        let 今 = self.位置;
        if !self.逆質量.零か() {
            self.位置 = 今.変位を足す((今 - self.前の位置) + 重力の変位);
        }
        self.前の位置 = 今;
    }

    pub(super) fn 補正を足す(&mut self, 補正: 変位<ワールド>) {
        self.位置 = self.位置.変位を足す(補正);
    }
}
