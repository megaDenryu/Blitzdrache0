//! 剛体の参照計算の生成と実行が拒む入力。台帳とコンプライアンスと静止長の型付きエラーを包み、バッチの添字の不正を自分の枝で持つ。

use thiserror::Error;

use super::rotational_compliance::回転のコンプライアンスエラー;
use crate::constraint_graph::点添字;
use crate::rigid_body::{剛体の識別子, 剛体エラー};
use crate::xpbd::コンプライアンスエラー;

#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 剛体の参照計算エラー {
    #[error("剛体の台帳の操作に失敗した: {0}")]
    台帳(#[from] 剛体エラー),
    #[error("コンプライアンスの刻み依存量を作れない: {0}")]
    コンプライアンス(#[from] コンプライアンスエラー),
    #[error("回転のコンプライアンスの刻み依存量を作れない: {0}")]
    回転のコンプライアンス(#[from] 回転のコンプライアンスエラー),
    #[error("拘束が同じ剛体{剛体:?}を両側に持つ")]
    同じ剛体を結ぶ拘束 { 剛体: 剛体の識別子 },
    #[error("拘束が指す点添字{添字:?}が点の数{点の数}の範囲外である")]
    点添字が範囲外 { 添字: 点添字, 点の数: usize },
    #[error("細分数は1以上でなければならない")]
    細分数が零,
}
