//! 2つの剛体の局所点どうしを一致させる拘束(判断10の2つ目。剛体と剛体の接続拘束)。距離拘束の静止長0の形を姿勢自由度で解く。
//!   p_A = x_A + R(q_A) r̄_A、p_B = x_B + R(q_B) r̄_B、d = p_B − p_A、C = |d|、n = d ÷ C(AからBへ向かう単位向き)
//!   有効逆質量 = w̃_A + w̃_B(各 w̃ = w + (r × n)ᵀ I⁻¹ (r × n))、Δλ = (−C − α̃λ) ÷ (有効逆質量 + α̃)
//!   A の勾配は −n、B の勾配は +n であり、補正は判断9の式で各剛体の w と I⁻¹ の比に分配される
//! 退化(両方が動かせない・2点が一致)は非数を作らずに理由の枝を返し、λは変えない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断9」「判断10」。

use blitz_math::{ローカル, 変位, 逆キログラム};

use super::body_connection_result::接続拘束の一回の射影の結果;
use super::correction::姿勢自由度の補正;
use super::participant::姿勢自由度の参加者;
use crate::xpbd::{
    コンプライアンス, コンプライアンスエラー, ラグランジュ乗数, 刻み幅, 向きが定まる最小の距離
};

/// 静的な引数: 両剛体の局所点とコンプライアンス。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接続拘束の引数 {
    pub 局所点a: 変位<ローカル>,
    pub 局所点b: 変位<ローカル>,
    pub コンプライアンス: コンプライアンス,
}

impl 接続拘束の引数 {
    pub fn 生成する(
        局所点a: 変位<ローカル>, 局所点b: 変位<ローカル>, コンプライアンス: コンプライアンス
    ) -> Self {
        Self {
            局所点a,
            局所点b,
            コンプライアンス,
        }
    }

    pub fn 刻み幅で解く係数を導く(
        &self, 刻み幅: 刻み幅
    ) -> Result<接続拘束の一刻みの係数, コンプライアンスエラー> {
        Ok(接続拘束の一刻みの係数 {
            局所点a: self.局所点a,
            局所点b: self.局所点b,
            刻み依存量: self.コンプライアンス.刻み依存量(刻み幅)?,
        })
    }
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接続拘束の一刻みの係数 {
    局所点a: 変位<ローカル>,
    局所点b: 変位<ローカル>,
    刻み依存量: 逆キログラム,
}

impl 接続拘束の一刻みの係数 {
    /// 正典式の1回の反復。呼び出し側は2つの補正を各剛体の予測の状態へ適用し、更新後の乗数を次の反復へ渡す。
    pub fn 一回射影する(
        &self,
        a: &姿勢自由度の参加者,
        b: &姿勢自由度の参加者,
        乗数: ラグランジュ乗数,
    ) -> 接続拘束の一回の射影の結果 {
        if a.動かせないか() && b.動かせないか() {
            return 接続拘束の一回の射影の結果::両方が動かせない;
        }
        let (腕a, 腕b) = (a.配置().腕(self.局所点a), b.配置().腕(self.局所点b));
        let 差 = b.配置().重心の位置().変位を足す(腕b) - a.配置().重心の位置().変位を足す(腕a);
        let 拘束違反 = 差.長さ();
        let Ok(向き) = 差.単位方向() else {
            return 接続拘束の一回の射影の結果::一致している;
        };
        if 拘束違反 < 向きが定まる最小の距離 {
            return 接続拘束の一回の射影の結果::一致している;
        }
        let 有効逆質量 = a.一般化逆質量(腕a, 向き) + b.一般化逆質量(腕b, 向き);
        let 乗数の増分 = ラグランジュ乗数::長さを逆質量で割って生成する(
            (拘束違反 + 乗数 * self.刻み依存量) * -1.0,
            有効逆質量 + self.刻み依存量,
        );
        接続拘束の一回の射影の結果::補正した {
            補正a: 姿勢自由度の補正::点に作用する乗数を分配する(a, 腕a, 向き.逆を向く方向(), 乗数の増分),
            補正b: 姿勢自由度の補正::点に作用する乗数を分配する(b, 腕b, 向き, 乗数の増分),
            更新後のラグランジュ乗数: 乗数 + 乗数の増分,
        }
    }
}
