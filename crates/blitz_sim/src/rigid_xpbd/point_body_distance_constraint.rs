//! 点自由度と剛体上の局所点の距離拘束(判断10の剛体と点のバッチ)。布の頂点を剛体の局所点へ接続する拘束の式であり、点自由度と姿勢自由度が同じ拘束へ参加する最初の形である。
//!   p = x + R(q) r̄、d = p − 点、C = |d| − 静止長、n = d ÷ |d|(点から剛体上の点へ向かう単位向き)
//!   有効逆質量 = w_点 + w̃_剛体(w̃ = w + (r × n)ᵀ I⁻¹ (r × n))、Δλ = (−C − α̃λ) ÷ (有効逆質量 + α̃)
//!   点の勾配は −n(補正 = −w_点 Δλ n)、剛体の勾配は +n(判断9の式で並進と回転へ分配)
//! 実証はIssue #43(強結合)で行い、本便は式と検査を置く。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断10」。

use blitz_math::{ローカル, 変位, 逆キログラム};

use super::correction::姿勢自由度の補正;
use super::participant::姿勢自由度の参加者;
use super::point_body_distance_result::点と剛体の距離拘束の一回の射影の結果;
use crate::xpbd::{
    コンプライアンス, コンプライアンスエラー, ラグランジュ乗数, 刻み幅, 向きが定まる最小の距離, 距離拘束の参加点, 静止長
};

/// 静的な引数: 剛体の局所点・静止長・コンプライアンス。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 点と剛体の距離拘束の引数 {
    pub 局所点: 変位<ローカル>,
    pub 静止長: 静止長,
    pub コンプライアンス: コンプライアンス,
}

impl 点と剛体の距離拘束の引数 {
    pub fn 生成する(局所点: 変位<ローカル>, 静止長: 静止長, コンプライアンス: コンプライアンス) -> Self {
        Self {
            局所点,
            静止長,
            コンプライアンス,
        }
    }

    pub fn 刻み幅で解く係数を導く(
        &self,
        刻み幅: 刻み幅,
    ) -> Result<点と剛体の距離拘束の一刻みの係数, コンプライアンスエラー> {
        Ok(点と剛体の距離拘束の一刻みの係数 {
            局所点: self.局所点,
            静止長: self.静止長,
            刻み依存量: self.コンプライアンス.刻み依存量(刻み幅)?,
        })
    }
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 点と剛体の距離拘束の一刻みの係数 {
    局所点: 変位<ローカル>,
    静止長: 静止長,
    刻み依存量: 逆キログラム,
}

impl 点と剛体の距離拘束の一刻みの係数 {
    /// 正典式の1回の反復。呼び出し側は点の補正を位置へ足し、剛体の補正を予測の状態へ適用し、更新後の乗数を次の反復へ渡す。
    pub fn 一回射影する(
        &self,
        点: 距離拘束の参加点,
        剛体: &姿勢自由度の参加者,
        乗数: ラグランジュ乗数,
    ) -> 点と剛体の距離拘束の一回の射影の結果 {
        if 点.逆質量.零か() && 剛体.動かせないか() {
            return 点と剛体の距離拘束の一回の射影の結果::両方が動かせない;
        }
        let 腕 = 剛体.配置().腕(self.局所点);
        let 差 = 剛体.配置().重心の位置().変位を足す(腕) - 点.位置;
        let 距離 = 差.長さ();
        let Ok(向き) = 差.単位方向() else {
            return 点と剛体の距離拘束の一回の射影の結果::向きが定まらない;
        };
        if 距離 < 向きが定まる最小の距離 {
            return 点と剛体の距離拘束の一回の射影の結果::向きが定まらない;
        }
        let 拘束違反 = 距離 - self.静止長.値();
        let 有効逆質量 = 点.逆質量 + 剛体.一般化逆質量(腕, 向き);
        let 乗数の増分 = ラグランジュ乗数::長さを逆質量で割って生成する(
            (拘束違反 + 乗数 * self.刻み依存量) * -1.0,
            有効逆質量 + self.刻み依存量,
        );
        点と剛体の距離拘束の一回の射影の結果::補正した {
            点の補正: 変位::方向へ進む(向き, 乗数の増分 * 点.逆質量 * -1.0),
            剛体の補正: 姿勢自由度の補正::点に作用する乗数を分配する(剛体, 腕, 向き, 乗数の増分),
            更新後のラグランジュ乗数: 乗数 + 乗数の増分,
        }
    }
}
