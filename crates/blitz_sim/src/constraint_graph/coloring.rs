//! グラフ彩色: 同じ点を同時に触らない拘束の集合へ拘束を色分けする前計算。
//! 貪欲法(拘束を並びの順に見て、両端の点がまだ使っていない最小の色を与える)であり、決定的である。
//! 色ごとに連続した並びへ拘束を組み替えて持つのは、GPUが色ごとに1回のディスパッチで区間を処理するためである。

use super::constraint_index::拘束添字;
use super::graph::拘束グラフ;

/// 色1つが占める、並べ替えた拘束一覧の中の連続した区間。GPUのディスパッチ1回分である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 色の区間 {
    pub 開始: 拘束添字,
    pub 本数: u32,
}

/// 彩色の結果。拘束を色ごとに連続するよう並べ替えたグラフと、色ごとの区間を持つ。
#[derive(Debug, Clone, PartialEq)]
pub struct グラフ彩色 {
    並べ替えたグラフ: 拘束グラフ,
    色の区間一覧: Vec<色の区間>,
}

impl グラフ彩色 {
    pub fn 生成する(グラフ: &拘束グラフ) -> Self {
        let 色一覧 = グラフ.拘束へ貪欲に色を割り当てる();
        let 色の数 = 色一覧.iter().map(|色| 色 + 1).max().unwrap_or(0);
        let mut 並べ替えた = Vec::with_capacity(グラフ.拘束の数());
        let mut 色の区間一覧 = Vec::with_capacity(色の数);
        for 色 in 0..色の数 {
            let 開始 = 拘束添字::配列添字から生成する(並べ替えた.len());
            for (拘束, 割り当て) in グラフ.拘束一覧().iter().zip(&色一覧) {
                if *割り当て == 色 {
                    並べ替えた.push(*拘束);
                }
            }
            let 本数 = u32::try_from(並べ替えた.len() - 開始.配列添字()).unwrap_or_else(|_| panic!("色の本数がu32に収まらない"));
            色の区間一覧.push(色の区間 { 開始, 本数 });
        }
        Self {
            並べ替えたグラフ: グラフ.拘束を並べ替えた(並べ替えた),
            色の区間一覧,
        }
    }

    /// 色ごとに連続した並びへ組み替えたグラフ。GPUの拘束バッファはこの並びで書く。
    pub fn 並べ替えたグラフ(&self) -> &拘束グラフ {
        &self.並べ替えたグラフ
    }

    pub fn 色の区間一覧(&self) -> &[色の区間] {
        &self.色の区間一覧
    }

    pub fn 色の数(&self) -> usize {
        self.色の区間一覧.len()
    }
}
