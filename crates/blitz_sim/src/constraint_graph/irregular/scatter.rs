//! 点を立方体の中へ決定的に散らす工程。受け取るのは生成器と点の数と一辺、返すのはワールドの位置の並びである。
//! 用途番号を成分ごとに分けるのは、同じ添字から独立した3つの値を得るためである。

use blitz_math::{メートル, ワールド, 位置, 決定的な値の生成器, 用途番号};

/// 散布が使う用途番号。近い点の選択(`neighbors`)の番号と重ならないように、この領域の番号はここが1つ持つ。
const 横の用途番号: u64 = 1;
const 縦の用途番号: u64 = 2;
const 奥の用途番号: u64 = 3;

pub(super) fn 点を散らす(生成器: &決定的な値の生成器, 点の数: u32, 一辺: メートル) -> Vec<位置<ワールド>> {
    (0..u64::from(点の数))
        .map(|添字| {
            位置::生成する(
                一辺 * 生成器.零以上一未満(添字, 用途番号::番号から生成する(横の用途番号)),
                一辺 * 生成器.零以上一未満(添字, 用途番号::番号から生成する(縦の用途番号)),
                一辺 * 生成器.零以上一未満(添字, 用途番号::番号から生成する(奥の用途番号)),
            )
        })
        .collect()
}
