//! 目標拘束の毎刻み与える入力。目標位置と、その拘束が効いているかを持つ。
//! 有効と無効を型で持つのは、掴むと離すを「拘束の着脱」として表すためであり(判断6)、離した粒子の質量を復元する仕組みを要らなくする。
//! 世界固定点はこの目標を刻みを跨いで動かさない特別な場合であり、動く目標(スキン済み頂点・掴んだ手)は拘束反復の前にその刻みの値を確定する。

use blitz_math::{ワールド, 位置};

/// 目標拘束が効いているかどうか。無効の拘束は反復で読まれない(乗数も0のまま)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 目標拘束の有効 {
    有効,
    無効,
}

/// 目標拘束の1本が指す目標位置と、その拘束の有効と無効。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 目標拘束の目標 {
    pub 位置: 位置<ワールド>,
    pub 有効: 目標拘束の有効,
}

impl 目標拘束の目標 {
    /// 与えた位置へ効いている目標(世界固定点・アタッチの初期値)。
    pub fn 有効な位置(位置: 位置<ワールド>) -> Self {
        Self {
            位置,
            有効: 目標拘束の有効::有効,
        }
    }

    /// まだ効いていない目標(掴む前の掴みの枠)。位置は掴んだときに介入が与える。
    pub fn 無効な位置(位置: 位置<ワールド>) -> Self {
        Self {
            位置,
            有効: 目標拘束の有効::無効,
        }
    }
}
