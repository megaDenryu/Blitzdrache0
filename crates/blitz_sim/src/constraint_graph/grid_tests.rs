//! 規則格子の題材の検査: 点の数と拘束の本数が布の格子の理論値に一致すること、上端の行だけが固定であること、
//! 平方数でない点の数を拒むことを見る。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, 逆キログラム};

use super::error::拘束グラフエラー;
use super::grid::{規則格子の仕様, 規則格子の拘束グラフを作る};
use crate::xpbd::コンプライアンス;

pub(super) fn 検査の格子の仕様(点の数: u32) -> 規則格子の仕様 {
    規則格子の仕様 {
        点の数,
        粒子間隔: メートル::生成する(0.05),
        一点の逆質量: 逆キログラム::生成する(100.0).unwrap(),
        コンプライアンス: コンプライアンス::生成する(0.005).unwrap(),
    }
}

#[test]
fn 一辺nの格子は構造とせん断の本数が理論値になり上端の行だけが固定である() {
    let 一辺 = 8u32;
    let グラフ = 規則格子の拘束グラフを作る(&検査の格子の仕様(一辺 * 一辺)).unwrap();
    assert_eq!(グラフ.点の数(), 64);
    let 理論値 = 2 * 一辺 * (一辺 - 1) + 2 * (一辺 - 1) * (一辺 - 1);
    assert_eq!(グラフ.拘束の数(), usize::try_from(理論値).unwrap());
    let 固定の数 = グラフ.点一覧().iter().filter(|点| 点.逆質量.零か()).count();
    assert_eq!(固定の数, 8);
    assert!(グラフ.点一覧()[..8].iter().all(|点| 点.逆質量.零か()));
    assert!(グラフ.点一覧()[8..].iter().all(|点| !点.逆質量.零か()));
}

#[test]
fn 平方数でない点の数は拒む() {
    assert!(matches!(
        規則格子の拘束グラフを作る(&検査の格子の仕様(1000)),
        Err(拘束グラフエラー::規則格子の点の数が平方数でない { 点の数: 1000 })
    ));
}
