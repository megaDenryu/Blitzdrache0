//! 目標拘束のバッチの生成が課す不変条件の検査: 範囲外の点添字と同じ点の2本目を拒み、通ったバッチは並びと添字を保つ。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 位置};

use super::indexed_target_constraint::添字付き目標拘束;
use super::point_index::点添字;
use super::target_batch::目標拘束のバッチ;
use super::target_index::目標拘束添字;
use super::target_state::{目標拘束の有効, 目標拘束の目標};
use crate::constraint_graph::拘束グラフエラー;
use crate::xpbd::目標拘束の引数;

fn 目標(点: u32, 有効か: bool) -> (添字付き目標拘束, 目標拘束の目標) {
    let 位置 = 位置::<ワールド>::生成する(メートル::生成する(1.0), メートル::生成する(2.0), メートル::生成する(3.0));
    let 目標 = if 有効か {
        目標拘束の目標::有効な位置(位置)
    } else {
        目標拘束の目標::無効な位置(位置)
    };
    (添字付き目標拘束::生成する(点添字::生成する(点), 目標拘束の引数::硬い()), 目標)
}

#[test]
fn 別の点を持つ目標拘束は並びと有効を保って通る() {
    let バッチ = 目標拘束のバッチ::生成する(4, vec![目標(0, true), 目標(3, false)]).unwrap();
    assert_eq!(バッチ.拘束の数(), 2);
    assert_eq!(バッチ.拘束一覧()[1].粒子, 点添字::生成する(3));
    assert_eq!(バッチ.初期の目標一覧()[0].有効, 目標拘束の有効::有効);
    assert_eq!(バッチ.初期の目標一覧()[1].有効, 目標拘束の有効::無効);
    assert_eq!(バッチ.添字(1), 目標拘束添字::生成する(1));
}

/// 反証: 同じ点を2本の目標拘束が持つと、1色の中で同じ粒子へ競合して書く。
#[test]
fn 同じ点を持つ2本目と範囲外の点添字を拒む() {
    assert!(matches!(
        目標拘束のバッチ::生成する(4, vec![目標(2, true), 目標(2, false)]),
        Err(拘束グラフエラー::同じ点を持つ目標拘束が複数ある { .. })
    ));
    assert!(matches!(
        目標拘束のバッチ::生成する(4, vec![目標(4, true)]),
        Err(拘束グラフエラー::目標拘束の点添字が範囲外 { 点の数: 4, .. })
    ));
    assert_eq!(目標拘束のバッチ::空().拘束の数(), 0);
}
