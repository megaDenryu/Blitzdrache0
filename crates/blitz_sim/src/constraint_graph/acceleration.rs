//! 全点へ一様に掛かる加速度。重力と、拘束を破るために数刻みだけ掛ける外力の加速度をこの1つの型で表す。
//! 一刻みの変位へ写す口を持つのは、参照計算とGPUの定数が受け取る量が加速度に刻み幅の2乗を掛けた変位だからであり、一刻みの速度の変化へ写す口は剛体の予測が速度を持つために足した。

use blitz_math::{メートル毎秒毎秒, ワールド, 変位, 速度};

use crate::xpbd::刻み幅;

/// ワールドの3成分の加速度。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 一様な加速度 {
    x: メートル毎秒毎秒,
    y: メートル毎秒毎秒,
    z: メートル毎秒毎秒,
}

impl 一様な加速度 {
    pub fn 成分から生成する(x: メートル毎秒毎秒, y: メートル毎秒毎秒, z: メートル毎秒毎秒) -> Self {
        Self { x, y, z }
    }

    pub fn 零() -> Self {
        let 零 = メートル毎秒毎秒::生成する(0.0);
        Self { x: 零, y: 零, z: 零 }
    }

    /// 静止した点がこの加速度で1つの刻みに動く変位(加速度 × 刻み幅の2乗)。
    pub fn 一刻みの変位(&self, 刻み幅: 刻み幅) -> 変位<ワールド> {
        let 秒 = 刻み幅.秒();
        変位::成分から生成する(self.x * 秒 * 秒, self.y * 秒 * 秒, self.z * 秒 * 秒)
    }

    /// 静止した点がこの加速度で1つの刻みに得る速度の変化(加速度 × 刻み幅)。剛体の細分の予測が v ← v + h g に使う。
    pub fn 一刻みの速度の変化(&self, 刻み幅: 刻み幅) -> 速度<ワールド> {
        let 秒 = 刻み幅.秒();
        速度::成分から生成する(self.x * 秒, self.y * 秒, self.z * 秒)
    }

    /// 境界向けの生値。GPUの定数へ書く側だけが読む。
    pub fn 成分の値(&self) -> [f32; 3] {
        [self.x.値(), self.y.値(), self.z.値()]
    }
}

impl std::ops::Add for 一様な加速度 {
    type Output = Self;
    fn add(self, 右辺: Self) -> Self {
        Self {
            x: メートル毎秒毎秒::生成する(self.x.値() + 右辺.x.値()),
            y: メートル毎秒毎秒::生成する(self.y.値() + 右辺.y.値()),
            z: メートル毎秒毎秒::生成する(self.z.値() + 右辺.z.値()),
        }
    }
}
