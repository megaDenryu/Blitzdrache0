//! 参加する点の添字を持つ目標拘束。`目標拘束の引数`が持たない点の添字を足したものであり、目標拘束のバッチの拘束一覧の1件である。

use super::point_index::点添字;
use crate::xpbd::目標拘束の引数;

/// 目標拘束のバッチの1本。目標位置は持たず、同じ添字の`目標拘束の目標`が毎刻みの入力として持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 添字付き目標拘束 {
    pub 粒子: 点添字,
    pub 引数: 目標拘束の引数,
}

impl 添字付き目標拘束 {
    pub fn 生成する(粒子: 点添字, 引数: 目標拘束の引数) -> Self {
        Self { 粒子, 引数 }
    }
}
