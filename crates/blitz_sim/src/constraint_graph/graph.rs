//! 拘束グラフの本体。点の一覧と拘束の一覧を持ち、生成で添字の範囲を検査する。
//! 点と拘束の数がu32に収まることも生成が保証するため、GPUの添字と隣接表はそのまま32ビットで書ける。

use super::error::拘束グラフエラー;
use super::indexed_constraint::添字付き距離拘束;
use super::point_index::点添字;
use super::point_state::点自由度の初期状態;

/// 点自由度の集まりと距離拘束の集まり。拘束が指す添字はすべて点の一覧の範囲内である。
#[derive(Debug, Clone, PartialEq)]
pub struct 拘束グラフ {
    点一覧: Vec<点自由度の初期状態>,
    拘束一覧: Vec<添字付き距離拘束>,
}

impl 拘束グラフ {
    /// 範囲外の添字を持つ拘束と、u32に収まらない数を型付きエラーで拒む。
    pub fn 生成する(
        点一覧: Vec<点自由度の初期状態>, 拘束一覧: Vec<添字付き距離拘束>
    ) -> Result<Self, 拘束グラフエラー> {
        if u32::try_from(点一覧.len()).is_err() {
            return Err(拘束グラフエラー::点の数が過大 { 点の数: 点一覧.len() });
        }
        if u32::try_from(拘束一覧.len()).is_err() {
            return Err(拘束グラフエラー::拘束の数が過大 {
                拘束の数: 拘束一覧.len()
            });
        }
        for 拘束 in &拘束一覧 {
            for 添字 in [拘束.a, 拘束.b] {
                if 添字.配列添字() >= 点一覧.len() {
                    return Err(拘束グラフエラー::点添字が範囲外 {
                        添字, 点の数: 点一覧.len()
                    });
                }
            }
        }
        Ok(Self { 点一覧, 拘束一覧 })
    }

    pub fn 点一覧(&self) -> &[点自由度の初期状態] {
        &self.点一覧
    }

    pub fn 拘束一覧(&self) -> &[添字付き距離拘束] {
        &self.拘束一覧
    }

    pub fn 点の数(&self) -> usize {
        self.点一覧.len()
    }

    pub fn 拘束の数(&self) -> usize {
        self.拘束一覧.len()
    }

    /// 点ごとに、その点を参加点に持つ拘束の本数。同時に更新する方式の緩和係数と、隣接表の区間がこれから決まる。
    pub fn 点ごとの接続数(&self) -> Vec<u32> {
        let mut 接続数 = vec![0u32; self.点一覧.len()];
        for 拘束 in &self.拘束一覧 {
            接続数[拘束.a.配列添字()] += 1;
            接続数[拘束.b.配列添字()] += 1;
        }
        接続数
    }

    // 各拘束へ色(0始まり)を貪欲に割り当てた並び。点ごとに使用済みの色を持ち、両端の和集合に無い最小の色を選ぶ。決定的である。
    // グラフに対する純粋な演算であり自然な主語がグラフであるため、彩色の型の関連関数でなくここのメソッドに置く。呼び手は彩色だけなので親モジュールまでに絞る。
    pub(super) fn 拘束へ貪欲に色を割り当てる(&self) -> Vec<usize> {
        let mut 点が使った色: Vec<Vec<usize>> = vec![Vec::new(); self.点一覧.len()];
        let mut 色一覧 = Vec::with_capacity(self.拘束一覧.len());
        for 拘束 in &self.拘束一覧 {
            let mut 色 = 0;
            while 点が使った色[拘束.a.配列添字()].contains(&色) || 点が使った色[拘束.b.配列添字()].contains(&色) {
                色 += 1;
            }
            点が使った色[拘束.a.配列添字()].push(色);
            点が使った色[拘束.b.配列添字()].push(色);
            色一覧.push(色);
        }
        色一覧
    }

    /// 拘束の並びを入れ替えた同じグラフ。彩色が色ごとに連続した並びへ組み替えるときに使う。
    /// 前提: 渡す並びは元の拘束一覧の並べ替えであり、この型の内部からしか呼ばれない。
    pub(super) fn 拘束を並べ替えた(&self, 拘束一覧: Vec<添字付き距離拘束>) -> Self {
        Self {
            点一覧: self.点一覧.clone(),
            拘束一覧,
        }
    }

    /// 点の添字を配列の添字から作る。点の数がu32に収まることは生成が保証済みである。
    pub fn 点添字(&self, 配列添字: usize) -> 点添字 {
        点添字::生成する(u32::try_from(配列添字).unwrap_or_else(|_| panic!("点の添字がu32に収まらない: {配列添字}")))
    }
}
