//! 拘束グラフの生成が拒む入力と、題材の生成で下位の型が拒んだ入力の包み。

use thiserror::Error;

use super::point_index::点添字;
use crate::xpbd::{コンプライアンスエラー, 静止長エラー};

/// 拘束グラフの生成と題材の生成で起こりうる失敗。
#[derive(Debug, Clone, PartialEq, Error)]
pub enum 拘束グラフエラー {
    #[error("拘束が指す点添字{添字:?}が点の数{点の数}の範囲外である")]
    点添字が範囲外 { 添字: 点添字, 点の数: usize },
    #[error("拘束が同じ点{点:?}を両側に持つ")]
    同じ点を結ぶ拘束 { 点: 点添字 },
    #[error("点の数{点の数}がu32の範囲を超える")]
    点の数が過大 { 点の数: usize },
    #[error("拘束の数{拘束の数}がu32の範囲を超える")]
    拘束の数が過大 { 拘束の数: usize },
    #[error("点の数{点の数}は規則格子の一辺の2乗でなければならない")]
    規則格子の点の数が平方数でない { 点の数: u32 },
    #[error("不規則グラフの点の数{点の数}は接続数の上限{上限}より多くなければならない")]
    不規則グラフの点が少なすぎる { 点の数: u32, 上限: u32 },
    #[error("布の格子を生成できない: {0}")]
    布の格子を生成できない(#[from] crate::cloth::布生成エラー),
    #[error("静止長を作れない: {0}")]
    静止長を作れない(#[from] 静止長エラー),
    #[error("コンプライアンスを作れない: {0}")]
    コンプライアンスを作れない(#[from] コンプライアンスエラー),
    #[error("逆質量を作れない: {0}")]
    逆質量を作れない(#[from] blitz_math::質量エラー),
}
