//! 不規則な拘束グラフ。決定的な値の生成器で点を立方体の中へ散らし、各点から近い点へ点ごとに違う本数(1〜上限)の
//! 距離拘束を張る。接続数が不均一なグラフであり、将来の剛体の接触と関節を想定した形である(剛体そのものは作らない)。
//! 点の散布は`scatter`、近い点の選択は`neighbors`が持つ。

mod neighbors;
mod scatter;

use blitz_math::{メートル, 決定的な値の生成器, 逆キログラム};

use super::error::拘束グラフエラー;
use super::graph::拘束グラフ;
use super::indexed_constraint::添字付き距離拘束;
use super::point_state::点自由度の初期状態;
use crate::xpbd::{コンプライアンス, 距離拘束の引数, 静止長};

/// 点ごとの拘束の本数の上限。1からこの数までを点ごとに違う数で張る。
const 接続数の上限: u32 = 12;

/// 固定する点の間隔。この間隔ごとに1点を固定し、重力で全体が落ち続けないようにする。
const 固定する点の間隔: usize = 64;

/// 不規則グラフの題材の仕様。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 不規則グラフの仕様 {
    pub 点の数: u32,
    pub 種: u64,
    pub 立方体の一辺: メートル,
    pub 一点の逆質量: 逆キログラム,
    pub コンプライアンス: コンプライアンス,
}

pub fn 不規則な拘束グラフを作る(仕様: &不規則グラフの仕様) -> Result<拘束グラフ, 拘束グラフエラー> {
    if 仕様.点の数 <= 接続数の上限 {
        return Err(拘束グラフエラー::不規則グラフの点が少なすぎる {
            点の数: 仕様.点の数,
            上限: 接続数の上限,
        });
    }
    let 生成器 = 決定的な値の生成器::種の値から生成する(仕様.種);
    let 位置一覧 = scatter::点を散らす(&生成器, 仕様.点の数, 仕様.立方体の一辺);
    let 点一覧: Vec<点自由度の初期状態> = 位置一覧
        .iter()
        .enumerate()
        .map(|(添字, 位置)| {
            let 逆質量 = if 添字 % 固定する点の間隔 == 0 {
                逆キログラム::零()
            } else {
                仕様.一点の逆質量
            };
            点自由度の初期状態::生成する(*位置, 逆質量)
        })
        .collect();
    let mut 拘束一覧 = Vec::new();
    for 対 in neighbors::近い点の対を選ぶ(&生成器, &位置一覧, 接続数の上限) {
        let 距離 = (位置一覧[対.b.配列添字()] - 位置一覧[対.a.配列添字()]).長さ();
        let 引数 = 距離拘束の引数::生成する(静止長::生成する(距離)?, 仕様.コンプライアンス);
        拘束一覧.push(添字付き距離拘束::生成する(対.a, 対.b, 引数)?);
    }
    拘束グラフ::生成する(点一覧, 拘束一覧)
}
