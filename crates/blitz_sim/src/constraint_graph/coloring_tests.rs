//! 彩色の検査: 同じ色の中に同じ点を共有する拘束が無いこと、並べ替えが元の拘束を1本も落とさず増やさないこと、
//! 規則格子と不規則グラフで色の数が接続数の上限の範囲に収まることを見る。

#![allow(clippy::unwrap_used)]

use std::collections::BTreeSet;

use super::coloring::グラフ彩色;
use super::graph::拘束グラフ;
use super::test_fixtures::三角形と尾のグラフ;
use super::{不規則な拘束グラフを作る, 規則格子の拘束グラフを作る};

fn 色の中で点が重ならない(彩色: &グラフ彩色) {
    let 拘束一覧 = 彩色.並べ替えたグラフ().拘束一覧();
    for 区間 in 彩色.色の区間一覧() {
        let 開始 = 区間.開始.配列添字();
        let 本数 = usize::try_from(区間.本数).unwrap();
        let mut 触った点 = BTreeSet::new();
        for 拘束 in &拘束一覧[開始..開始 + 本数] {
            assert!(触った点.insert(拘束.a), "色の中で点{:?}が重なった", 拘束.a);
            assert!(触った点.insert(拘束.b), "色の中で点{:?}が重なった", 拘束.b);
        }
    }
}

fn 並べ替えは元の拘束の置換である(元: &拘束グラフ, 彩色: &グラフ彩色) {
    let 元の集合: BTreeSet<(u32, u32)> = 元.拘束一覧().iter().map(|拘束| (拘束.a.値(), 拘束.b.値())).collect();
    let 並べ替えの集合: BTreeSet<(u32, u32)> = 彩色.並べ替えたグラフ().拘束一覧().iter().map(|拘束| (拘束.a.値(), 拘束.b.値())).collect();
    assert_eq!(元の集合, 並べ替えの集合);
    assert_eq!(元.拘束の数(), 彩色.並べ替えたグラフ().拘束の数());
    let 区間の合計: u32 = 彩色.色の区間一覧().iter().map(|区間| 区間.本数).sum();
    assert_eq!(usize::try_from(区間の合計).unwrap(), 元.拘束の数());
}

#[test]
fn 三角形は3色で尾は先頭の色へ入る() {
    let グラフ = 三角形と尾のグラフ();
    let 彩色 = グラフ彩色::生成する(&グラフ);
    assert_eq!(彩色.色の数(), 3);
    色の中で点が重ならない(&彩色);
    並べ替えは元の拘束の置換である(&グラフ, &彩色);
}

#[test]
fn 規則格子と不規則グラフの彩色は点を共有せず色の数が接続数の上限の範囲に収まる() {
    let 格子 = 規則格子の拘束グラフを作る(&super::grid_tests::検査の格子の仕様(16 * 16)).unwrap();
    let 格子の彩色 = グラフ彩色::生成する(&格子);
    色の中で点が重ならない(&格子の彩色);
    並べ替えは元の拘束の置換である(&格子, &格子の彩色);
    // 拘束(辺)の貪欲な彩色は、1本が両端で最大接続数 - 1本ずつと競合するため、色の数が2 × 最大接続数 - 1を超えない。
    // 格子の最大接続数は8である。
    assert!(格子の彩色.色の数() <= 15, "格子の色の数{}", 格子の彩色.色の数());

    let 不規則 = 不規則な拘束グラフを作る(&super::irregular_tests::検査の不規則の仕様(256)).unwrap();
    let 不規則の彩色 = グラフ彩色::生成する(&不規則);
    色の中で点が重ならない(&不規則の彩色);
    並べ替えは元の拘束の置換である(&不規則, &不規則の彩色);
    let 最大接続数 = 不規則.点ごとの接続数().into_iter().max().unwrap();
    assert!(usize::try_from(2 * 最大接続数 - 1).unwrap() >= 不規則の彩色.色の数());
}
