//! 不規則グラフの題材の検査: 同じ種から同じグラフが出ること(決定性)、接続数が不均一であること、
//! 同じ対が2度張られないこと、少なすぎる点の数を拒むことを見る。

#![allow(clippy::unwrap_used)]

use std::collections::BTreeSet;

use blitz_math::{メートル, 逆キログラム};

use super::error::拘束グラフエラー;
use super::irregular::{不規則な拘束グラフを作る, 不規則グラフの仕様};
use crate::xpbd::コンプライアンス;

pub(super) fn 検査の不規則の仕様(点の数: u32) -> 不規則グラフの仕様 {
    不規則グラフの仕様 {
        点の数,
        種: 7,
        立方体の一辺: メートル::生成する(2.0),
        一点の逆質量: 逆キログラム::生成する(100.0).unwrap(),
        コンプライアンス: コンプライアンス::生成する(0.005).unwrap(),
    }
}

#[test]
fn 同じ種からは同じグラフが出て接続数は不均一である() {
    let 一回目 = 不規則な拘束グラフを作る(&検査の不規則の仕様(256)).unwrap();
    let 二回目 = 不規則な拘束グラフを作る(&検査の不規則の仕様(256)).unwrap();
    assert_eq!(一回目, 二回目);
    let 接続数 = 一回目.点ごとの接続数();
    let 種類: BTreeSet<u32> = 接続数.iter().copied().collect();
    assert!(種類.len() >= 4, "接続数の種類が{}しかない", 種類.len());
    assert!(接続数.iter().all(|数| *数 >= 1));
    assert_eq!(一回目.点一覧().iter().filter(|点| 点.逆質量.零か()).count(), 4);
}

#[test]
fn 同じ対は2度張られず静止長は初期の距離に等しい() {
    let グラフ = 不規則な拘束グラフを作る(&検査の不規則の仕様(256)).unwrap();
    let mut 対の集合 = BTreeSet::new();
    for 拘束 in グラフ.拘束一覧() {
        assert!(拘束.a < 拘束.b);
        assert!(対の集合.insert((拘束.a, 拘束.b)));
        let 距離 = (グラフ.点一覧()[拘束.b.配列添字()].位置 - グラフ.点一覧()[拘束.a.配列添字()].位置).長さ();
        assert_eq!(距離, 拘束.引数.静止長.値());
    }
}

#[test]
fn 接続数の上限以下の点の数は拒む() {
    assert!(matches!(
        不規則な拘束グラフを作る(&検査の不規則の仕様(12)),
        Err(拘束グラフエラー::不規則グラフの点が少なすぎる { 点の数: 12, .. })
    ));
}
