//! 隣接表の検査: 区間の開始が接続数の累積であること、各点の区間にその点を持つ拘束だけが拘束添字の昇順で並ぶこと、
//! 1語の符号化が拘束添字と側を復元できることを見る。

#![allow(clippy::unwrap_used)]

use super::adjacency::{点ごとの拘束の隣接表, 隣接の側};
use super::point_index::点添字;
use super::test_fixtures::三角形と尾のグラフ;

#[test]
fn 区間の開始は接続数の累積である() {
    let グラフ = 三角形と尾のグラフ();
    let 表 = 点ごとの拘束の隣接表::生成する(&グラフ);
    assert_eq!(表.区間の開始一覧(), &[0, 2, 4, 7, 8]);
    assert_eq!(表.項目一覧().len(), グラフ.拘束の数() * 2);
}

#[test]
fn 各点の区間にはその点を持つ拘束だけが昇順で並ぶ() {
    let グラフ = 三角形と尾のグラフ();
    let 表 = 点ごとの拘束の隣接表::生成する(&グラフ);
    for (配列添字, _) in グラフ.点一覧().iter().enumerate() {
        let 点 = グラフ.点添字(配列添字);
        let 項目一覧 = 表.点の項目(点);
        assert_eq!(項目一覧.len(), usize::try_from(表.接続数(点)).unwrap());
        for 窓 in 項目一覧.windows(2) {
            assert!(窓[0].拘束 < 窓[1].拘束);
        }
        for 項目 in 項目一覧 {
            let 拘束 = グラフ.拘束一覧()[項目.拘束.配列添字()];
            assert_eq!(拘束.側(点), Some(項目.側));
        }
    }
}

#[test]
fn 一語の符号化は最下位ビットが側で残りが拘束添字である() {
    let グラフ = 三角形と尾のグラフ();
    let 表 = 点ごとの拘束の隣接表::生成する(&グラフ);
    let 点2 = 点添字::生成する(2);
    let 語一覧: Vec<u32> = 表.点の項目(点2).iter().map(|項目| 項目.一語へ符号化する()).collect();
    // 点2は拘束1(0-2)のb側・拘束2(1-2)のb側・拘束3(2-3)のa側に参加する(1×2+1・2×2+1・3×2)。
    assert_eq!(語一覧, vec![3, 5, 6]);
    assert_eq!(表.点の項目(点2)[2].側, 隣接の側::A);
}
