//! 拘束グラフの検査が共有する題材。三角形(0-1・0-2・1-2)に尾(2-3)を付けた4点4拘束の小さなグラフと、
//! 検査用の引数の組み立てを持つ。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 位置, 逆キログラム};

use super::graph::拘束グラフ;
use super::indexed_constraint::添字付き距離拘束;
use super::point_index::点添字;
use super::point_state::点自由度の初期状態;
use crate::xpbd::{コンプライアンス, 距離拘束の引数, 静止長};

pub(super) fn 引数(静止長: f32, コンプライアンス: f32) -> 距離拘束の引数 {
    距離拘束の引数::生成する(
        静止長::生成する(メートル::生成する(静止長)).unwrap(),
        コンプライアンス::生成する(コンプライアンス).unwrap(),
    )
}

pub(super) fn 点(x: f32, y: f32, 逆質量: f32) -> 点自由度の初期状態 {
    点自由度の初期状態::生成する(
        位置::<ワールド>::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(0.0)),
        逆キログラム::生成する(逆質量).unwrap(),
    )
}

pub(super) fn 拘束(a: u32, b: u32, 静止長: f32) -> 添字付き距離拘束 {
    添字付き距離拘束::生成する(点添字::生成する(a), 点添字::生成する(b), 引数(静止長, 0.0)).unwrap()
}

/// 点0を固定した三角形と尾。拘束の並びは 0-1・0-2・1-2・2-3 である。
pub(super) fn 三角形と尾のグラフ() -> 拘束グラフ {
    拘束グラフ::生成する(
        vec![点(0.0, 0.0, 0.0), 点(1.0, 0.0, 1.0), 点(0.0, 1.0, 1.0), 点(0.0, 2.0, 1.0)],
        vec![拘束(0, 1, 1.0), 拘束(0, 2, 1.0), 拘束(1, 2, 1.5), 拘束(2, 3, 1.0)],
    )
    .unwrap()
}
