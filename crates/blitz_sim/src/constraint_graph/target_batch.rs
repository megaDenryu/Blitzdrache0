//! 目標拘束のバッチ(判断4の密なバッチ)。静的な引数(点の添字とコンプライアンス)の一覧と、毎刻み与える入力(目標位置と有効)の初期値の一覧を、同じ添字で持つ。
//! 生成が課す不変条件は3つである。点の添字が点の数の範囲内であること、同じ点を持つ目標拘束が高々1本であること(目標拘束は点を1つしか触らないため、
//! この条件でバッチ全体が彩色の1色になり、GPUは1回のディスパッチで解ける)、本数がu32に収まること(GPUの添字と介入の拘束添字が32ビットである)。

use super::error::拘束グラフエラー;
use super::indexed_target_constraint::添字付き目標拘束;
use super::target_index::目標拘束添字;
use super::target_state::目標拘束の目標;

#[derive(Debug, Clone, PartialEq)]
pub struct 目標拘束のバッチ {
    拘束一覧: Vec<添字付き目標拘束>,
    初期の目標一覧: Vec<目標拘束の目標>,
}

impl 目標拘束のバッチ {
    /// 範囲外の点添字・同じ点を持つ2本目・u32に収まらない本数を型付きエラーで拒む。
    pub fn 生成する(点の数: usize, 一覧: Vec<(添字付き目標拘束, 目標拘束の目標)>) -> Result<Self, 拘束グラフエラー> {
        if u32::try_from(一覧.len()).is_err() {
            return Err(拘束グラフエラー::目標拘束の数が過大 { 拘束の数: 一覧.len() });
        }
        let mut 点を使った = vec![false; 点の数];
        for (拘束, _) in &一覧 {
            let 配列添字 = 拘束.粒子.配列添字();
            if 配列添字 >= 点の数 {
                return Err(拘束グラフエラー::目標拘束の点添字が範囲外 {
                    添字: 拘束.粒子, 点の数
                });
            }
            if 点を使った[配列添字] {
                return Err(拘束グラフエラー::同じ点を持つ目標拘束が複数ある { 点: 拘束.粒子 });
            }
            点を使った[配列添字] = true;
        }
        let (拘束一覧, 初期の目標一覧) = 一覧.into_iter().unzip();
        Ok(Self {
            拘束一覧, 初期の目標一覧
        })
    }

    /// 目標拘束を1本も持たないバッチ。
    pub fn 空() -> Self {
        Self {
            拘束一覧: Vec::new(),
            初期の目標一覧: Vec::new(),
        }
    }

    pub fn 拘束一覧(&self) -> &[添字付き目標拘束] {
        &self.拘束一覧
    }

    pub fn 初期の目標一覧(&self) -> &[目標拘束の目標] {
        &self.初期の目標一覧
    }

    pub fn 拘束の数(&self) -> usize {
        self.拘束一覧.len()
    }

    /// 配列の添字から目標拘束の添字を作る。本数がu32に収まることは生成が保証済みである。
    pub fn 添字(&self, 配列添字: usize) -> 目標拘束添字 {
        目標拘束添字::生成する(u32::try_from(配列添字).unwrap_or_else(|_| panic!("目標拘束の添字がu32に収まらない: {配列添字}")))
    }
}
