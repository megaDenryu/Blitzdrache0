//! 規則格子の拘束グラフ。現在の布と同じ一辺n×nの格子の構造(縦横)とせん断(斜め)の距離拘束であり、
//! 生成は布の格子の生成(`crate::cloth`)をそのまま使う。上端の行を固定し、残りは同じ質量の可動点である。

use blitz_math::{メートル, 逆キログラム};

use super::error::拘束グラフエラー;
use super::graph::拘束グラフ;
use crate::cloth::{布の物性, 布を生成する, 布仕様};
use crate::xpbd::{コンプライアンス, 曲げのコンプライアンス};

/// 規則格子の題材の仕様。点の数は一辺の2乗でなければならない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 規則格子の仕様 {
    pub 点の数: u32,
    pub 粒子間隔: メートル,
    pub 一点の逆質量: 逆キログラム,
    pub コンプライアンス: コンプライアンス,
}

pub fn 規則格子の拘束グラフを作る(仕様: &規則格子の仕様) -> Result<拘束グラフ, 拘束グラフエラー> {
    let 一辺 = 一辺を求める(仕様.点の数)?;
    // 布仕様の総質量は布の生成が均等質量へ割るためだけに読むが、逆質量はこの関数が仕様の値で上書きする。
    let mut 布 = 布を生成する(&布仕様::生成する(一辺, 仕様.粒子間隔.値(), 1.0, [0.0, 0.0, 0.0])?)?;
    for 粒子 in &mut 布.粒子一覧 {
        粒子.逆質量 = 仕様.一点の逆質量.値();
    }
    for 上端 in &布.上端行の粒子添字一覧 {
        布.粒子一覧[usize::try_from(*上端).unwrap_or_else(|_| panic!("上端の添字がusizeに収まらない"))].逆質量 = 0.0;
    }
    // 計測の題材は距離拘束だけを持つため、曲げのコンプライアンスは写されない硬い値である。
    布.拘束グラフへ写す(&布の物性::一様に生成する(
        仕様.コンプライアンス,
        曲げのコンプライアンス::硬い(),
    ))
}

/// 点の数の平方根が整数であることを確かめて一辺を返す。整数の範囲で数えるのは、数値の縮小変換を使わないためである。
fn 一辺を求める(点の数: u32) -> Result<u32, 拘束グラフエラー> {
    let mut 一辺 = 0u32;
    while 一辺.saturating_mul(一辺) < 点の数 {
        一辺 += 1;
    }
    if 一辺 * 一辺 != 点の数 {
        return Err(拘束グラフエラー::規則格子の点の数が平方数でない { 点の数 });
    }
    Ok(一辺)
}
