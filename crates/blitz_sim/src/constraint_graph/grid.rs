//! 規則格子の拘束グラフ。現在の布と同じ一辺n×nの格子の構造(縦横)とせん断(斜め)の距離拘束であり、
//! 生成は布の格子の生成(`crate::cloth`)をそのまま使う。上端の行を固定し、残りは同じ質量の可動点である。

use blitz_math::{メートル, ワールド, 位置, 逆キログラム};

use super::error::拘束グラフエラー;
use super::graph::拘束グラフ;
use super::indexed_constraint::添字付き距離拘束;
use super::point_index::点添字;
use super::point_state::点自由度の初期状態;
use crate::cloth::{布を生成する, 布仕様};
use crate::xpbd::{コンプライアンス, 距離拘束の引数, 静止長};

/// 規則格子の題材の仕様。点の数は一辺の2乗でなければならない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 規則格子の仕様 {
    pub 点の数: u32,
    pub 粒子間隔: メートル,
    pub 一点の逆質量: 逆キログラム,
    pub コンプライアンス: コンプライアンス,
}

pub fn 規則格子の拘束グラフを作る(仕様: &規則格子の仕様) -> Result<拘束グラフ, 拘束グラフエラー> {
    let 一辺 = 一辺を求める(仕様.点の数)?;
    // 布仕様の総質量は布の生成が均等質量へ割るためだけに読むが、逆質量はこの関数が仕様の値で上書きする。
    let 布 = 布を生成する(&布仕様::生成する(一辺, 仕様.粒子間隔.値(), 1.0, [0.0, 0.0, 0.0])?)?;
    let 点一覧 = 布
        .粒子一覧
        .iter()
        .enumerate()
        .map(|(添字, 粒子)| {
            let 固定か = 布
                .上端行の粒子添字一覧
                .iter()
                .any(|上端| usize::try_from(*上端).is_ok_and(|上端| 上端 == 添字));
            let 位置 = 位置::<ワールド>::生成する(
                メートル::生成する(粒子.位置[0]),
                メートル::生成する(粒子.位置[1]),
                メートル::生成する(粒子.位置[2]),
            );
            点自由度の初期状態::生成する(
                位置,
                if 固定か {
                    逆キログラム::零()
                } else {
                    仕様.一点の逆質量
                },
            )
        })
        .collect();
    let mut 拘束一覧 = Vec::with_capacity(布.距離拘束一覧.len());
    for 拘束 in &布.距離拘束一覧 {
        let 引数 = 距離拘束の引数::生成する(静止長::生成する(メートル::生成する(拘束.静止長))?, 仕様.コンプライアンス);
        拘束一覧.push(添字付き距離拘束::生成する(
            点添字::生成する(拘束.粒子a添字),
            点添字::生成する(拘束.粒子b添字),
            引数,
        )?);
    }
    拘束グラフ::生成する(点一覧, 拘束一覧)
}

/// 点の数の平方根が整数であることを確かめて一辺を返す。整数の範囲で数えるのは、数値の縮小変換を使わないためである。
fn 一辺を求める(点の数: u32) -> Result<u32, 拘束グラフエラー> {
    let mut 一辺 = 0u32;
    while 一辺.saturating_mul(一辺) < 点の数 {
        一辺 += 1;
    }
    if 一辺 * 一辺 != 点の数 {
        return Err(拘束グラフエラー::規則格子の点の数が平方数でない { 点の数 });
    }
    Ok(一辺)
}
