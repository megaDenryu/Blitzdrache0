//! 点自由度の初期状態。位置と逆質量を持ち、速度は0から始める(計測の題材は静止から重力と外力で動き出す)。

use blitz_math::{ワールド, 位置, 逆キログラム};

/// 拘束グラフの1つの点自由度の初期状態。逆質量0は固定した点である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 点自由度の初期状態 {
    pub 位置: 位置<ワールド>,
    pub 逆質量: 逆キログラム,
}

impl 点自由度の初期状態 {
    pub fn 生成する(位置: 位置<ワールド>, 逆質量: 逆キログラム) -> Self {
        Self { 位置, 逆質量 }
    }
}
