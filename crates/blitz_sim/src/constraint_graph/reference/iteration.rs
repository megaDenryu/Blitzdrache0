//! 参照計算の反復1回。更新の順序ごとに、正典式の一回の射影を全拘束へ当てて位置と乗数を更新する。
//! 退化の枝(両方が固定・向きが定まらない)は補正0で乗数を変えない。GPUの写しも同じ扱いである。

use blitz_math::{ワールド, 変位};

use super::schedule::反復の更新の順序;
use super::拘束グラフの参照計算;
use crate::xpbd::{距離拘束の一回の射影の結果, 距離拘束の参加点};

impl 拘束グラフの参照計算 {
    pub(super) fn 一回反復する(&mut self) {
        match self.順序 {
            反復の更新の順序::逐次 => self.逐次に反復する(),
            反復の更新の順序::同時 => self.同時に反復する(),
        }
    }

    /// 拘束を並びの順に射影し、補正を直ちに位置へ足す。
    fn 逐次に反復する(&mut self) {
        for 添字 in 0..self.拘束一覧.len() {
            let (補正a, 補正b) = self.拘束を射影して乗数を更新する(添字);
            let 拘束 = self.拘束一覧[添字];
            self.位置一覧[拘束.a.配列添字()] = self.位置一覧[拘束.a.配列添字()].変位を足す(補正a);
            self.位置一覧[拘束.b.配列添字()] = self.位置一覧[拘束.b.配列添字()].変位を足す(補正b);
        }
    }

    /// 全拘束を同じ位置から射影して補正を点ごとに集め、集め終えてから位置へ足す。
    fn 同時に反復する(&mut self) {
        let mut 集めた補正 = vec![変位::<ワールド>::零(); self.位置一覧.len()];
        for 添字 in 0..self.拘束一覧.len() {
            let (補正a, 補正b) = self.拘束を射影して乗数を更新する(添字);
            let 拘束 = self.拘束一覧[添字];
            集めた補正[拘束.a.配列添字()] = 集めた補正[拘束.a.配列添字()] + 補正a;
            集めた補正[拘束.b.配列添字()] = 集めた補正[拘束.b.配列添字()] + 補正b;
        }
        for (位置, 補正) in self.位置一覧.iter_mut().zip(集めた補正) {
            *位置 = 位置.変位を足す(補正);
        }
    }

    /// 1本の拘束を現在の位置で射影し、緩和係数を掛けた増分で乗数を更新して、同じ係数を掛けた補正を返す。
    fn 拘束を射影して乗数を更新する(&mut self, 添字: usize) -> (変位<ワールド>, 変位<ワールド>) {
        let 拘束 = self.拘束一覧[添字];
        let a = 距離拘束の参加点::生成する(self.位置一覧[拘束.a.配列添字()], self.逆質量一覧[拘束.a.配列添字()]);
        let b = 距離拘束の参加点::生成する(self.位置一覧[拘束.b.配列添字()], self.逆質量一覧[拘束.b.配列添字()]);
        let 乗数 = self.乗数一覧[添字];
        match self.係数一覧[添字].一回射影する(a, b, 乗数) {
            距離拘束の一回の射影の結果::補正した {
                補正a,
                補正b,
                更新後のラグランジュ乗数,
            } => {
                let 緩和 = self.順序.緩和係数(&拘束, &self.隣接表);
                self.乗数一覧[添字] = 乗数 + (更新後のラグランジュ乗数 - 乗数).比で伸ばす(緩和);
                (補正a.比で伸ばす(緩和), 補正b.比で伸ばす(緩和))
            }
            距離拘束の一回の射影の結果::両方が固定 | 距離拘束の一回の射影の結果::向きが定まらない => {
                (変位::零(), 変位::零())
            }
        }
    }
}
