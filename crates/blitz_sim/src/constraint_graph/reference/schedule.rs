//! 反復の中で拘束の補正をどの順で位置へ反映するかの別。GPUの並列方式が持つ更新の順序を、CPUの参照計算が同じ形で再現する。
//!
//! 逐次は、拘束を並びの順に1本ずつ射影して直ちに位置へ反映する(ガウス・ザイデル型)。グラフ彩色の方式が色の中の
//! 拘束を同時に触っても、同じ点を共有しないため逐次と同じ結果になる。
//! 同時は、全拘束を同じ位置から射影し、補正を集めてから反映する(ヤコビ型)。原子加算と二段階の方式がこれである。
//! 同時に反映する補正は、接続数の多い点で重なって過剰補正になり発散するため、拘束ごとに両端の接続数の大きい方の
//! 逆数を緩和係数として乗数の増分と補正の両方へ掛ける。乗数と補正へ同じ係数を掛けるのは、乗数が「実際に加えた
//! 補正の総量」であるという正典の意味を保つためである(補正だけを縮めると乗数が加えていない力を数える)。

use super::super::adjacency::点ごとの拘束の隣接表;
use super::super::indexed_constraint::添字付き距離拘束;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 反復の更新の順序 {
    逐次,
    同時,
}

impl 反復の更新の順序 {
    /// その拘束の乗数の増分と補正へ掛ける緩和係数。逐次は常に1である。
    pub(super) fn 緩和係数(self, 拘束: &添字付き距離拘束, 隣接表: &点ごとの拘束の隣接表) -> f32 {
        match self {
            Self::逐次 => 1.0,
            Self::同時 => 同時の緩和係数(隣接表.接続数(拘束.a), 隣接表.接続数(拘束.b)),
        }
    }
}

/// 両端の接続数の大きい方の逆数。GPUの同時に更新する方式(`shaders/xpbd_projection.slang`)が同じ式を持つ。
pub fn 同時の緩和係数(接続数a: u32, 接続数b: u32) -> f32 {
    let 大きい方 = 接続数a.max(接続数b).max(1);
    1.0 / f32::from(u16::try_from(大きい方).unwrap_or(u16::MAX))
}
