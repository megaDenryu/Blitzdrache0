//! 拘束グラフの参照計算: 正典式(`crate::xpbd`)を同じ反復回数だけ回し、GPUの3方式の結果と突き合わせる基準を作る。
//! 状態は位置と前の位置と拘束ごとのラグランジュ乗数であり、速度は位置と前の位置の差で表す(ベルレ形)。
//! 速度を別に持たないのは、位置ベースの解法が読むのが位置だけであり、GPUの方式も同じ2本のバッファで進めるためである。
//! 一刻みの工程は`step`、反復の1回は`iteration`、更新の順序の別は`schedule`が持つ。

mod iteration;
mod schedule;
mod step;

use blitz_math::{ワールド, 位置, 逆キログラム};

pub use schedule::{反復の更新の順序, 同時の緩和係数};

use super::adjacency::点ごとの拘束の隣接表;
use super::error::拘束グラフエラー;
use super::graph::拘束グラフ;
use super::indexed_constraint::添字付き距離拘束;
use crate::xpbd::{ラグランジュ乗数, 刻み幅, 距離拘束の一刻みの係数};

/// 参照計算の状態。拘束の並びは渡したグラフの並びそのものであり、ラグランジュ乗数の並びもそれに従う。
pub struct 拘束グラフの参照計算 {
    拘束一覧: Vec<添字付き距離拘束>,
    係数一覧: Vec<距離拘束の一刻みの係数>,
    隣接表: 点ごとの拘束の隣接表,
    逆質量一覧: Vec<逆キログラム>,
    位置一覧: Vec<位置<ワールド>>,
    前の位置一覧: Vec<位置<ワールド>>,
    乗数一覧: Vec<ラグランジュ乗数>,
    順序: 反復の更新の順序,
    刻み幅: 刻み幅,
}

impl 拘束グラフの参照計算 {
    /// 刻み幅を受けて全拘束の一刻みの係数を1度だけ導く(判断8の工程6)。
    pub fn 生成する(
        グラフ: &拘束グラフ, 順序: 反復の更新の順序, 刻み幅: 刻み幅
    ) -> Result<Self, 拘束グラフエラー> {
        let mut 係数一覧 = Vec::with_capacity(グラフ.拘束の数());
        for 拘束 in グラフ.拘束一覧() {
            係数一覧.push(拘束.引数.刻み幅で解く係数を導く(刻み幅)?);
        }
        let 位置一覧: Vec<位置<ワールド>> = グラフ.点一覧().iter().map(|点| 点.位置).collect();
        Ok(Self {
            拘束一覧: グラフ.拘束一覧().to_vec(),
            係数一覧,
            隣接表: 点ごとの拘束の隣接表::生成する(グラフ),
            逆質量一覧: グラフ.点一覧().iter().map(|点| 点.逆質量).collect(),
            前の位置一覧: 位置一覧.clone(),
            乗数一覧: vec![ラグランジュ乗数::零(); グラフ.拘束の数()],
            位置一覧,
            順序,
            刻み幅,
        })
    }

    pub fn 位置一覧(&self) -> &[位置<ワールド>] {
        &self.位置一覧
    }

    /// 直近の刻みの反復を終えた時点のラグランジュ乗数。次の刻みの開始で零へ戻る。
    pub fn ラグランジュ乗数一覧(&self) -> &[ラグランジュ乗数] {
        &self.乗数一覧
    }

    /// 現在の位置での拘束違反の二乗平均の平方根。収束の度合いを方式どうしで比べる量である。
    pub fn 拘束違反の二乗平均平方根(&self) -> f64 {
        拘束違反の二乗平均平方根(&self.拘束一覧, &self.位置一覧)
    }
}

/// 位置の並びに対する拘束違反(現在の距離 − 静止長)の符号付きの平均。伸びていれば正であり、硬さの記録が伸びの向きを読むために使う。
pub fn 拘束違反の平均(拘束一覧: &[添字付き距離拘束], 位置一覧: &[位置<ワールド>]) -> f64 {
    let Ok(本数) = u32::try_from(拘束一覧.len()) else {
        panic!("拘束の数がu32に収まらない(拘束グラフの生成が保証するはずの不変条件の破れ)");
    };
    if 本数 == 0 {
        return 0.0;
    }
    let 合計: f64 = 拘束一覧
        .iter()
        .map(|拘束| {
            let 距離 = (位置一覧[拘束.b.配列添字()] - 位置一覧[拘束.a.配列添字()]).長さ();
            f64::from((距離 - 拘束.引数.静止長.値()).値())
        })
        .sum();
    合計 / f64::from(本数)
}

/// 位置の並びに対する拘束違反(現在の距離 − 静止長)の二乗平均の平方根。GPUの読み戻しにも同じ式を当てる。
pub fn 拘束違反の二乗平均平方根(拘束一覧: &[添字付き距離拘束], 位置一覧: &[位置<ワールド>]) -> f64 {
    let Ok(本数) = u32::try_from(拘束一覧.len()) else {
        panic!("拘束の数がu32に収まらない(拘束グラフの生成が保証するはずの不変条件の破れ)");
    };
    if 本数 == 0 {
        return 0.0;
    }
    let 二乗和: f64 = 拘束一覧
        .iter()
        .map(|拘束| {
            let 距離 = (位置一覧[拘束.b.配列添字()] - 位置一覧[拘束.a.配列添字()]).長さ();
            f64::from((距離 - 拘束.引数.静止長.値()).値()).powi(2)
        })
        .sum();
    (二乗和 / f64::from(本数)).sqrt()
}
