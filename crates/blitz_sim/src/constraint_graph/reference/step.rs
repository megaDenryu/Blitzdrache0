//! 参照計算の一刻み。工程は判断8の部分列であり、予測(重力と外力の変位を足す)→乗数を零へ→反復→確定である。
//! 速度の再構成は位置と前の位置の差が速度そのものであるため工程として存在しない(ベルレ形)。

use super::super::acceleration::一様な加速度;
use super::拘束グラフの参照計算;
use crate::xpbd::ラグランジュ乗数;

impl 拘束グラフの参照計算 {
    /// 1つの物理刻みを進める。加速度は重力と外力の和であり、固定した点(逆質量0)は動かさない。
    pub fn 一刻み進める(&mut self, 加速度: 一様な加速度, 反復回数: u32) {
        let 変位 = 加速度.一刻みの変位(self.刻み幅);
        for 添字 in 0..self.位置一覧.len() {
            if self.逆質量一覧[添字].零か() {
                self.前の位置一覧[添字] = self.位置一覧[添字];
                continue;
            }
            let 今 = self.位置一覧[添字];
            let 移動 = 今 - self.前の位置一覧[添字];
            self.前の位置一覧[添字] = 今;
            self.位置一覧[添字] = 今.変位を足す(移動 + 変位);
        }
        for 乗数 in &mut self.乗数一覧 {
            *乗数 = ラグランジュ乗数::零();
        }
        for _ in 0..反復回数 {
            self.一回反復する();
        }
    }
}
