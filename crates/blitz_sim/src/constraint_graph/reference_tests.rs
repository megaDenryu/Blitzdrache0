//! 参照計算の検査: 固定した点が動かないこと、逐次と同時のどちらも反復で拘束違反が減ること、
//! 刻みの開始で乗数が零へ戻ってから累積することを見る。反証として、同時の緩和係数を外すと接続数の多い点で
//! 拘束違反が減らないことも固定する(緩和を外した式は書かず、逐次より同時の残差が大きいことだけを見る)。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル毎秒毎秒, 秒};

use super::acceleration::一様な加速度;
use super::reference::{反復の更新の順序, 拘束グラフの参照計算};
use super::test_fixtures::三角形と尾のグラフ;
use crate::xpbd::刻み幅;

fn 重力() -> 一様な加速度 {
    一様な加速度::成分から生成する(
        メートル毎秒毎秒::生成する(0.0),
        メートル毎秒毎秒::生成する(-9.8),
        メートル毎秒毎秒::生成する(0.0),
    )
}

fn 刻み幅() -> 刻み幅 {
    刻み幅::生成する(秒::生成する(1.0 / 60.0)).unwrap()
}

#[test]
fn 固定した点は動かず反復で拘束違反が減る() {
    for 順序 in [反復の更新の順序::逐次, 反復の更新の順序::同時] {
        let グラフ = 三角形と尾のグラフ();
        let mut 参照 = 拘束グラフの参照計算::生成する(&グラフ, 順序, 刻み幅()).unwrap();
        let mut 反復なし = 拘束グラフの参照計算::生成する(&グラフ, 順序, 刻み幅()).unwrap();
        for _ in 0..30 {
            参照.一刻み進める(重力(), 8);
            反復なし.一刻み進める(重力(), 0);
        }
        assert_eq!(参照.位置一覧()[0], グラフ.点一覧()[0].位置, "{順序:?}で固定した点が動いた");
        assert!(
            参照.拘束違反の二乗平均平方根() < 反復なし.拘束違反の二乗平均平方根() * 0.1,
            "{順序:?}: 反復あり{} 反復なし{}",
            参照.拘束違反の二乗平均平方根(),
            反復なし.拘束違反の二乗平均平方根()
        );
        assert!(参照.ラグランジュ乗数一覧().iter().any(|乗数| 乗数.値() != 0.0));
    }
}

#[test]
fn 乗数は刻みの開始で零へ戻り反復を回さない刻みでは零のままである() {
    let グラフ = 三角形と尾のグラフ();
    let mut 参照 = 拘束グラフの参照計算::生成する(&グラフ, 反復の更新の順序::逐次, 刻み幅()).unwrap();
    参照.一刻み進める(重力(), 4);
    assert!(参照.ラグランジュ乗数一覧().iter().any(|乗数| 乗数.値() != 0.0));
    参照.一刻み進める(重力(), 0);
    assert!(参照.ラグランジュ乗数一覧().iter().all(|乗数| 乗数.値() == 0.0));
}

#[test]
fn 同時の更新は逐次より収束が遅いが発散しない() {
    let グラフ = 三角形と尾のグラフ();
    let mut 逐次 = 拘束グラフの参照計算::生成する(&グラフ, 反復の更新の順序::逐次, 刻み幅()).unwrap();
    let mut 同時 = 拘束グラフの参照計算::生成する(&グラフ, 反復の更新の順序::同時, 刻み幅()).unwrap();
    for _ in 0..60 {
        逐次.一刻み進める(重力(), 4);
        同時.一刻み進める(重力(), 4);
    }
    assert!(逐次.拘束違反の二乗平均平方根() <= 同時.拘束違反の二乗平均平方根());
    assert!(同時.拘束違反の二乗平均平方根().is_finite() && 同時.拘束違反の二乗平均平方根() < 1.0);
}
