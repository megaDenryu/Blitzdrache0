//! シミュレーションドメインの設計意味オントロジー (Issue #137)。
//!
//! 型が設計上何であるか(状態・設定・工程)は `blitz_design` の共通の設計マーカーで言い、このモジュールは
//! シミュレーションだけが持つ語彙(時間尺度と、時間尺度に結び付いた状態と工程)を足す。
//!
//! 規則:
//! 1. `M` 接頭辞を持つトレイトはメソッドを持たない。
//! 2. `is-a` 関係のみ supertrait で表す。
//! 3. 1対1の関係は associated type で表す。
//! 4. 0..N / N..M の関係は generic な空トレイトで表す。

pub use blitz_design::{MDTO, M工程, M状態, M設定};

/// 設計上の役割: 時間尺度 (基本刻み、物理小刻み、拘束反復など)
pub trait M時間尺度 {}

/// 時間局所状態: 特定の時間尺度の間だけ生存する状態
pub trait M時間局所状態: M状態 {
    /// この状態が有効な時間尺度
    type 生存範囲: M時間尺度;
}

/// 更新工程: 特定の時間尺度を単位として実行される工程
pub trait M更新工程: M工程 {
    /// この工程が実行される時間周期
    type 実行周期: M時間尺度;
}

// -----------------------------------------------------------------------------
// 時間尺度の語彙 (値を持たない型レベル概念)
// -----------------------------------------------------------------------------

/// ゲーム全体の基本刻み (H = 1/60秒)
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 基本刻み {}

/// 基本刻みを n 分割した物理計算の1単位 (h = H / n)
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 物理小刻み {}

/// 1つの物理小刻み内で行われる拘束射影の反復
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 拘束反復 {}

impl M時間尺度 for 基本刻み {}
impl M時間尺度 for 物理小刻み {}
impl M時間尺度 for 拘束反復 {}
