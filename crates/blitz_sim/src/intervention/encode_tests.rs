//! 介入のバイト列にするの単体テスト(判断53・55): 固定長・件数一致・値の位置確認。

use blitz_math::{メートル, ワールド, 位置};

use super::encode::バイト列にする;
use super::kind::介入;
use crate::constraint_graph::目標拘束添字;

fn 語(バイト列: &[u8], 開始: usize) -> u32 {
    u32::from_le_bytes([バイト列[開始], バイト列[開始 + 1], バイト列[開始 + 2], バイト列[開始 + 3]])
}

fn 目標(x: f32, y: f32, z: f32) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

#[test]
fn バイト列長は件数times32になる() {
    let 一覧 = vec![
        介入::目標拘束を有効にする {
            拘束添字: 目標拘束添字::生成する(3),
            目標位置: 目標(1.0, 2.0, 3.0),
        },
        介入::目標拘束を無効にする {
            拘束添字: 目標拘束添字::生成する(5),
        },
        介入::インパルス {
            位置: [0.0, 0.0, 0.0],
            力: [1.0, 0.0, 0.0],
        },
    ];
    let バイト列 = バイト列にする(&一覧);
    assert_eq!(バイト列.len(), 一覧.len() * 32);
    assert_eq!(語(&バイト列, 64 + 4), u32::MAX);
}

#[test]
fn 有効にするの種別と拘束添字と目標位置が正しくエンコードされる() {
    let 一覧 = vec![介入::目標拘束を有効にする {
        拘束添字: 目標拘束添字::生成する(7),
        目標位置: 目標(1.5, -2.5, 3.5),
    }];
    let バイト列 = バイト列にする(&一覧);
    let x = f32::from_le_bytes([バイト列[16], バイト列[17], バイト列[18], バイト列[19]]);
    let y = f32::from_le_bytes([バイト列[20], バイト列[21], バイト列[22], バイト列[23]]);
    assert_eq!((語(&バイト列, 0), 語(&バイト列, 4)), (0, 7));
    assert_eq!((x, y), (1.5, -2.5));
}

#[test]
fn 無効にするの種別と拘束添字が正しくエンコードされる() {
    let 一覧 = vec![介入::目標拘束を無効にする {
        拘束添字: 目標拘束添字::生成する(42),
    }];
    let バイト列 = バイト列にする(&一覧);
    assert_eq!((語(&バイト列, 0), 語(&バイト列, 4)), (1, 42));
}
