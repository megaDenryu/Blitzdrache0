//! 介入のバイト列にするの単体テスト(判断53・55): 固定長・件数一致・値の位置確認。

use super::encode::バイト列にする;
use super::kind::介入;

#[test]
fn バイト列長は件数times32になる() {
    let 一覧 = vec![
        介入::掴む {
            粒子添字: 3,
            目標位置: [1.0, 2.0, 3.0],
        },
        介入::離す { 粒子添字: 5 },
        介入::インパルス {
            位置: [0.0, 0.0, 0.0],
            力: [1.0, 0.0, 0.0],
        },
    ];
    let バイト列 = バイト列にする(&一覧);
    assert_eq!(バイト列.len(), 一覧.len() * 32);
}

#[test]
fn 掴むの種別と粒子添字と目標位置が正しくエンコードされる() {
    let 一覧 = vec![介入::掴む {
        粒子添字: 7,
        目標位置: [1.5, -2.5, 3.5],
    }];
    let バイト列 = バイト列にする(&一覧);

    let 種別 = u32::from_le_bytes([バイト列[0], バイト列[1], バイト列[2], バイト列[3]]);
    let 粒子添字 = u32::from_le_bytes([バイト列[4], バイト列[5], バイト列[6], バイト列[7]]);
    let x = f32::from_le_bytes([バイト列[16], バイト列[17], バイト列[18], バイト列[19]]);

    assert_eq!(種別, 0);
    assert_eq!(粒子添字, 7);
    assert_eq!(x, 1.5);
}

#[test]
fn 離すの種別と粒子添字が正しくエンコードされる() {
    let 一覧 = vec![介入::離す { 粒子添字: 42 }];
    let バイト列 = バイト列にする(&一覧);

    let 種別 = u32::from_le_bytes([バイト列[0], バイト列[1], バイト列[2], バイト列[3]]);
    let 粒子添字 = u32::from_le_bytes([バイト列[4], バイト列[5], バイト列[6], バイト列[7]]);

    assert_eq!(種別, 1);
    assert_eq!(粒子添字, 42);
}
