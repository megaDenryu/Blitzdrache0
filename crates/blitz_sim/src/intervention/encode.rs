//! 介入のGPU転送用固定長エンコード(判断53)。
//!
//! レイアウト(1件32バイト、リトルエンディアン、std430相当):
//! - 0..4:   種別(u32)。0=目標拘束を有効にする 1=目標拘束を無効にする 2=インパルス
//! - 4..8:   目標拘束添字(u32)。インパルスは対象の拘束が無いため`u32::MAX`で埋める(GPUは目標拘束の数の範囲外として読まない)
//! - 8..12:  パディング(u32、常に0)
//! - 12..16: パディング(u32、常に0)
//! - 16..32: vec4相当(f32×4)。有効にする=目標位置+0.0、無効にする=すべて0.0、
//!   インパルス=位置+0.0
//!
//! 注意: インパルスは`位置`と`力`の2つのvec3を持つが、この32バイト固定長には
//! 6要素を収める余地が無いため`力`はエンコードしない。M9はGPU側でインパルスを
//! 消費しないため実害は無い。`力`を含む往復が要るならM10以降でレイアウト拡張が必要。

use super::kind::介入;

const 目標拘束を有効にする種別コード: u32 = 0;
const 目標拘束を無効にする種別コード: u32 = 1;
const インパルス種別コード: u32 = 2;
const 対象の拘束なし: u32 = u32::MAX;
const 介入1件のバイト数: usize = 32;

pub fn バイト列にする(介入一覧: &[介入]) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(介入一覧.len() * 介入1件のバイト数);
    for 対象 in 介入一覧 {
        バイト列.extend_from_slice(&介入1件をエンコードする(対象));
    }
    バイト列
}

fn 介入1件をエンコードする(対象: &介入) -> [u8; 32] {
    let (種別, 拘束添字, ペイロード) = match *対象 {
        介入::目標拘束を有効にする { 拘束添字, 目標位置 } => (
            目標拘束を有効にする種別コード,
            拘束添字.値(),
            [目標位置.x().値(), 目標位置.y().値(), 目標位置.z().値(), 0.0],
        ),
        介入::目標拘束を無効にする { 拘束添字 } => (目標拘束を無効にする種別コード, 拘束添字.値(), [0.0, 0.0, 0.0, 0.0]),
        介入::インパルス { 位置, 力: _ } => (インパルス種別コード, 対象の拘束なし, [位置[0], 位置[1], 位置[2], 0.0]),
    };

    let mut バイト列 = [0u8; 32];
    バイト列[0..4].copy_from_slice(&種別.to_le_bytes());
    バイト列[4..8].copy_from_slice(&拘束添字.to_le_bytes());
    for (添字, 成分) in ペイロード.iter().enumerate() {
        let 開始 = 16 + 添字 * 4;
        バイト列[開始..開始 + 4].copy_from_slice(&成分.to_le_bytes());
    }
    バイト列
}
