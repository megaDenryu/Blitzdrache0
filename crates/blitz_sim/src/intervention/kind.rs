//! 介入: プレイヤーイベントをシミュレーションへ流し込む型付きの値(判断53)。
//! 参照: `_doc/設計/シミュレーション層.md`「介入モデル」。

/// M9で使うのは`掴む`と`離す`(判断53)。`インパルス`はM10以降の利用を見越した型のみの
/// 用意で、GPU側の消費経路はまだ無い。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 介入 {
    掴む { 粒子添字: u32, 目標位置: [f32; 3] },
    離す { 粒子添字: u32 },
    インパルス { 位置: [f32; 3], 力: [f32; 3] },
}
