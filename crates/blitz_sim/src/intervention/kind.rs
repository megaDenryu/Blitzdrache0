//! 介入: プレイヤーイベントをシミュレーションへ流し込む型付きの値(判断53)。
//! 掴むと離すは「拘束の着脱」であり、目標拘束を有効にする(目標位置を与える)ことと無効にすることで表す(`_doc/設計/XPBD共通拘束基盤.md`「判断6」)。
//! 粒子の逆質量を書き換える介入は無い。掴んだ目標は押している間ずっと毎刻み与え直す連続量であり、有効にする介入がその刻みの目標位置を運ぶ。
//! 参照: `_doc/設計/シミュレーション層.md`「介入モデル」。

use blitz_math::{ワールド, 位置};

use crate::constraint_graph::目標拘束添字;

/// M9で使うのは`目標拘束を有効にする`(掴む)と`目標拘束を無効にする`(離す)。`インパルス`はM10以降の利用を見越した型のみの
/// 用意で、GPU側の消費経路はまだ無い。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 介入 {
    目標拘束を有効にする {
        拘束添字: 目標拘束添字,
        目標位置: 位置<ワールド>,
    },
    目標拘束を無効にする {
        拘束添字: 目標拘束添字,
    },
    インパルス {
        位置: [f32; 3],
        力: [f32; 3],
    },
}
