//! 細分の速度段階のうち剛体どうしの接触点(判断14)。
//! 剛体と静的世界の側(`pipeline_velocity`)と分けているのは、参加者が2つあり、どちらも起きているとは限らないためである。
//! 起きている動的剛体だけがこの細分の予測と再構成した速度を持つ。持たない剛体は動かせない参加者として扱い、速度を零とする。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断14」「判断18」。

use super::pipeline_error::接触の工程エラー;
use super::pipeline_solver::接触の解法ソルバー;
use super::substep_predict::細分の動的剛体;
use crate::rigid_body::{剛体, 剛体の識別子, 剛体エラー, 運動状態};
use crate::rigid_xpbd::姿勢自由度の参加者;
use crate::接触::contact_batches::接触拘束の二つのバッチ;
use crate::接触::island::接触島;
use crate::接触::velocity_stage::{接触の速度段階の結果, 接触点の法線の相対速度を求める};

impl 接触の解法ソルバー {
    pub(super) fn 島の剛体どうしの速度段階を解く(
        &self, 島: &接触島, バッチ: &mut 接触拘束の二つのバッチ, 動的剛体一覧: &mut [細分の動的剛体], 剛体一覧: &[剛体], 初回: bool
    ) -> Result<(), 接触の工程エラー> {
        let 剛体間区間 = 島.剛体どうしの接触拘束の区間();
        for 拘束 in 剛体間区間.可変スライスを切り出す(バッチ.剛体どうしの接触拘束を反復のために借りる()) {
            if !拘束.法線反力が在るか() {
                continue;
            }
            let (識別子第1, 識別子第2) = (拘束.引数().剛体第1, 拘束.引数().剛体第2);
            let 台帳第1 = 剛体一覧.get(識別子第1.配列添字()).ok_or(剛体エラー::剛体が登録されていない { 識別子: 識別子第1 })?;
            let 台帳第2 = 剛体一覧.get(識別子第2.配列添字()).ok_or(剛体エラー::剛体が登録されていない { 識別子: 識別子第2 })?;
            let (参加者第1, 速度第1) = 速度段階の参加者を組む(動的剛体一覧, 識別子第1, 台帳第1);
            let (参加者第2, 速度第2) = 速度段階の参加者を組む(動的剛体一覧, 識別子第2, 台帳第2);
            let 参加点第1 = 拘束.速度段階の剛体第1の参加点(&参加者第1, 速度第1);
            let 参加点第2 = 拘束.速度段階の剛体第2の参加点(&参加者第2, 速度第2);
            let 相対速度 = 接触点の法線の相対速度を求める(参加点第1, 参加点第2, 拘束.引数().接触法線);
            let 条件 = 拘束.速度段階の条件を組む(相対速度);
            let 結果 = if 初回 {
                self.速度段階.一点へ適用する(参加点第1, 参加点第2, 条件)
            } else {
                self.速度段階.一点へ反発だけ適用する(参加点第1, 参加点第2, 条件)
            };
            if let 接触の速度段階の結果::衝撃を適用した {
                適用後の第1の運動状態, 適用後の第2の運動状態,
            ..
            } = 結果
            {
                書き戻す(動的剛体一覧, 識別子第1, 適用後の第1の運動状態);
                書き戻す(動的剛体一覧, 識別子第2, 適用後の第2の運動状態);
            }
        }
        Ok(())
    }
}

// 起きている動的剛体だけがこの細分の予測と再構成した速度を持つ。持たない剛体は動かせない参加者として扱い、速度を零とする。
fn 速度段階の参加者を組む(動的剛体一覧: &[細分の動的剛体], 識別子: 剛体の識別子, 台帳剛体: &剛体) -> (姿勢自由度の参加者, 運動状態) {
    match 動的剛体一覧.iter().find(|剛体| 剛体.識別子 == 識別子) {
        Some(剛体) => (姿勢自由度の参加者::動的(*剛体.予測.配置(), 台帳剛体.質量特性()), 剛体.予測の運動状態),
        None => (姿勢自由度の参加者::動かせない(*台帳剛体.配置()), 運動状態::静止()),
    }
}

fn 書き戻す(動的剛体一覧: &mut [細分の動的剛体], 識別子: 剛体の識別子, 運動状態: 運動状態) {
    if let Some(剛体) = 動的剛体一覧.iter_mut().find(|剛体| 剛体.識別子 == 識別子) {
        剛体.予測の運動状態 = 運動状態;
    }
}
