//! 接触点集合1つの、法線と接線を同じ対称行列へ入れた連立方程式(判断12・判断13)。この型が持つのは点ごとの2つの行と、
//! 許容差の内側で行を積まなかった点の残差である。解く工程は`subset_search`が、行を積むかの判定は子の`row_admission`が、
//! 抜き出しが読む口(行の勾配・右辺・外した点の解放の増分)は子の`reduction_reading`が持つ。
//! 分けているのは、行を積むのが接触点集合の走査1回であるのに対し、解く工程が有効集合の部分集合ごとに
//! 抜き出しと求解を繰り返す別の局面だからである。
//! 法線の行は非貫通(判断12)がその反復に解くべき右辺 −C_n − α̃ λ_n をそのまま持ち、接線の行は錨の接線変位を零へ
//! 戻す右辺 −C_t を持つ(C_t が解けたと見なす許容差の内側の点の行は積まない。判断13の2026-09-12の改訂)。
//! 粘着の候補は、この2種類の行を1回の混合連立方程式として同時に解いた解である。
//! 法線を先に確定してから右辺が零の混合連立方程式を足す2段の形にすると、前段の有限回転を後段の線形化が取り消せず、
//! 錨の接線変位が反復のたびに作り直されて接線の乗数が積み増される。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

