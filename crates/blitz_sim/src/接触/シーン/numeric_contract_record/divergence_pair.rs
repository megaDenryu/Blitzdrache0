//! 保持する組と滑走する組の対と、その2つが分かれる細分を探す工程(Issue #59の原因の環の特定)。
//! 対にするのは、1つの条件だけが違って分類が違う2つの組である。3つ置く。許容差の倍率だけが違う対、
//! 鉛直軸まわりの回しだけが違う対、世界内の置き方だけが違う対である。
//! 1つの条件だけを変えた対を見るのは、分類を分けた原因をその条件へ絞るためである。条件が2つ以上違うと、
//! どちらが効いたか分けられない。
//! 綴る細分を「初めの数本」と「円錐を初めて超えた細分の前後」に絞るのは、滑走する組が早い段階で1度だけ円錐を
//! 超え、以後ずっと滑走したままになるという観測(56c0e642の表の錨の置き直しの延べ数)によるものである。
//! 分かれるのはその1本であり、そこから先を綴っても同じ状態が続くだけである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]

use super::diagnostic_case::数値契約の診断の一つの場合;

/// 1つの条件だけが違って分類が違う2つの組。
pub(super) struct 分類が分かれる組の対 {
    pub(super) 見出し: &'static str,
    pub(super) 保持する側の名前: &'static str,
    pub(super) 保持する側: 数値契約の診断の一つの場合,
    pub(super) 滑走する側の名前: &'static str,
    pub(super) 滑走する側: 数値契約の診断の一つの場合,
}

impl 分類が分かれる組の対 {
    /// 綴る細分の番号。初めの数本と、円錐を初めて超えた細分の1本前とその細分である。
    pub(super) fn 綴る細分の番号(&self, 初めの本数: usize, 探す上限: usize) -> Vec<usize> {
        let mut 番号 = (0..初めの本数).collect::<Vec<usize>>();
        if let Some(超えた) = self.滑走する側.円錐を初めて超えた細分の番号(探す上限) {
            番号.extend([超えた.saturating_sub(1), 超えた]);
        }
        番号.sort_unstable();
        番号.dedup();
        番号
    }

    /// 2つの側を名前とともに順に返す。綴る側が同じ工程で両方を回すための口である。
    pub(super) fn 二つの側(&self) -> [(&'static str, &数値契約の診断の一つの場合); 2] {
        [(self.保持する側の名前, &self.保持する側), (self.滑走する側の名前, &self.滑走する側)]
    }
}
