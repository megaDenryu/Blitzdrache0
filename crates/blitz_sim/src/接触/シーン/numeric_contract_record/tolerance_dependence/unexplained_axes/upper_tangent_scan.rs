#![cfg(test)]

use super::super::scene_variation::段階A1の場面からの一つの変更;
use super::amplifier_formula::増幅器の式;
use super::場合を組む;

const 振る傾きの正接: &[f32] = &[0.56, 0.58, 0.60];
const 細分の刻み幅の秒: f32 = 1.0 / 480.0;

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 五つの軸_走査の上端を正接零点六零まで伸ばして記録する() {
    for 傾きの正接 in 振る傾きの正接.iter().copied() {
        let 場合 = 場合を組む(傾きの正接, 0.0, 1.0, 段階A1の場面からの一つの変更::無し);
        let 記録 = super::一組を綴る(&場合);
        let 式 = 増幅器の式::正接と刻み幅から生成する(傾きの正接, 細分の刻み幅の秒);
        println!(
            "式の予測 正接{傾きの正接} 細分1の比 1倍={:.6} 実測={:.6}",
            式.二本目の細分の比の予測(記録[1].接線の行の許容差, 1.0),
            記録[1].最後の反復の後の円錐の比()
        );
    }
}
