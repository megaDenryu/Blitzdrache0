//! 段階A2の計測(い): 細分16本(刻み幅 1/960秒。判断19の本番の設定と同じ)の1組(Issue #59の第4段階。式の独立の検証)。
//! 本番の既定(右辺に δ)のまま、正接0.55・回し0度・許容差1倍で64細分と600刻みの分類を綴る。δ は座標の表現の刻みから
//! 決まり h に依らないため、式の項 m δ ÷ (g sinθ h²) は h を半分にすると4倍になる。式の予測は細分1の比 ≈ 0.641 で滑走で
//! あり、予測どおりなら式は独立に確かめられ、この欠陥は「解法が細分の細分化に対して収束していない」ことの現れである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

use super::super::scene_variation::段階A1の場面からの一つの変更;
use super::amplifier_formula::増幅器の式;
use super::場合を組む;

const 傾きの正接: f32 = 0.55;
const 十六本の細分の刻み幅の秒: f32 = 1.0 / 960.0;

#[test]
#[ignore = "計器であり合否を判定しない。実行は --ignored --nocapture を付ける"]
fn 五つの軸_細分十六本の一組を記録する() {
    let 場合 = 場合を組む(傾きの正接, 0.0, 1.0, 段階A1の場面からの一つの変更::細分数を十六にする);
    let 記録 = super::一組を綴る(&場合);
    let 式 = 増幅器の式::正接と刻み幅から生成する(傾きの正接, 十六本の細分の刻み幅の秒);
    let 許容差 = 記録[1].接線の行の許容差;
    println!(
        "式の予測(細分16本) gs={:.4e} δt={許容差:.4e} 細分1の比 1倍={:.6} 実測={:.6}",
        式.一細分の予測の接線変位(),
        式.二本目の細分の比の予測(許容差, 1.0),
        記録[1].最後の反復の後の円錐の比()
    );
}
