//! 細分ごとの円錐の比の振れを1行へ畳む数え(Issue #103の段階A6の追補)。畳むのは、最小・最大・平均と、
//! 隣り合う細分の比の差の絶対値の最大の4つである。数える工程(`cone_ratio_before_sliding`)から分けているのは、
//! あちらが場面を進める工程であり、こちらが進んだ結果を畳む数えだからである(`trajectory`と`trajectory_tally`の
//! 分け方と同じである)。
//! 細分0を数えないのは、初めの食い込みを解く過渡であり、そこだけ法線の乗数の合計が1桁大きいためである。
//! 参照: `_doc/計測/剛体の接触の静止摩擦の許容差依存の診断_2026-09-09.md`

#![cfg(test)]

/// 滑走するより前の細分の円錐の比の振れ。
pub(super) struct 円錐の比の振れ {
    数えた細分: usize,
    最小: f64,
    最大: f64,
    最大を出した細分: usize,
    合計: f64,
    直前の比: Option<f64>,
    隣り合う差の絶対値の最大: f64,
}

impl 円錐の比の振れ {
    pub(super) fn 零から始める() -> Self {
        Self {
            数えた細分: 0,
            最小: f64::INFINITY,
            最大: 0.0,
            最大を出した細分: 0,
            合計: 0.0,
            直前の比: None,
            隣り合う差の絶対値の最大: 0.0,
        }
    }

    /// 細分1本の比を数える。細分0は呼び出し側が渡さない。
    pub(super) fn 一細分の比を数える(&mut self, 細分の番号: usize, 比: f64) {
        self.数えた細分 += 1;
        self.最小 = self.最小.min(比);
        if 比 > self.最大 {
            self.最大 = 比;
            self.最大を出した細分 = 細分の番号;
        }
        self.合計 += 比;
        if let Some(直前) = self.直前の比 {
            self.隣り合う差の絶対値の最大 = self.隣り合う差の絶対値の最大.max((比 - 直前).abs());
        }
        self.直前の比 = Some(比);
    }

    /// 表へ綴る形。1本も数えていなければそう綴る。
    pub(super) fn 綴り(&self) -> String {
        if self.数えた細分 == 0 {
            return "数えた細分=0本".to_owned();
        }
        let 平均 = self.合計 / f64::from(u32::try_from(self.数えた細分).unwrap_or(u32::MAX));
        format!(
            "数えた細分={}本 比の最小={:.6} 比の最大={:.6}(細分{}) 比の平均={平均:.6} 幅={:.6} 隣り合う差の絶対値の最大={:.6}",
            self.数えた細分,
            self.最小,
            self.最大,
            self.最大を出した細分,
            self.最大 - self.最小,
            self.隣り合う差の絶対値の最大
        )
    }
}
