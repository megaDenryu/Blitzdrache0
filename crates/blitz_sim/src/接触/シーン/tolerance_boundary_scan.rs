//! 許容差の境界の走査(判断13の2026-09-12の実装の細目の反証(4)(b))。担当するのは、坂と箱をまとめて坂の面の法線の
//! 向きへ動かす長さと、受理の許容差の倍率を1組に束ね、傾きの正接を与えると600刻み走らせて保持と滑走の分類と坂に
//! 沿った変位を返すことである。合否の判定は持たない。
//! 走査を1つの型にするのは、同じ組を固定する検査(`tolerance_boundary_tests`)と表を綴る計器
//! (`tolerance_boundary_record`)の両方が同じ走らせ方を読むためである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断13: 静止摩擦は錨からの接線変位を零へ戻す位置拘束であり、クーロン円錐の内側でだけ効く」

#![cfg(test)]
#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::super::friction_coefficient::摩擦係数;
use super::super::normal_tangential_system::{解けたと見なす許容差の倍率, 試験の許容差の適用規則};
use super::slope_fixture::{一刻みの細分数, 坂の場面を移動と許容差の適用規則で組む};
use super::slope_geometry::坂の場面の条件;
use super::slope_holding::坂の箱の保持と滑走;
use super::static_friction_method::場面の静止摩擦の解き方;

const 保持を見る刻み数: usize = 600;

/// 法線の向きへ動かす長さと受理の許容差の倍率を固定した1本の走査。
pub(super) struct 許容差の境界の走査 {
    法線の向きへ動かす長さ: メートル,
    受理の倍率: 解けたと見なす許容差の倍率,
}

impl 許容差の境界の走査 {
    pub(super) fn 動かす長さと受理の倍率から生成する(法線の向きへ動かす長さ: f32, 受理の倍率: f32) -> Self {
        Self {
            法線の向きへ動かす長さ: メートル::生成する(法線の向きへ動かす長さ),
            受理の倍率: 解けたと見なす許容差の倍率::比から生成する(受理の倍率),
        }
    }

    /// 傾きの正接を1つ与えて600刻み走らせ、保持と滑走の分類と坂に沿った変位を返す。
    pub(super) fn 分類と坂に沿った変位(&self, 傾きの正接: f32) -> (坂の箱の保持と滑走, f32) {
        let 条件 = self.走らせる条件(傾きの正接);
        let 適用規則 = 試験の許容差の適用規則::本番と同じ適用規則().受理の倍率を差し替える(self.受理の倍率);
        let mut 場面 = 坂の場面を移動と許容差の適用規則で組む(&条件, self.法線の向きへ動かす長さ, 適用規則);
        let 初めの重心 = 場面.箱の配置.重心の位置();
        場面.細分を進める(保持を見る刻み数 * 一刻みの細分数);
        (場面.保持と滑走を分類する(初めの重心, &条件), 場面.坂に沿った変位(初めの重心, &条件))
    }

    /// 与えた走査の下端から数えて、連続して保持している最後の傾きの正接。下端で既に滑るなら無しである。
    pub(super) fn 下端から連続して保持する最後の正接(&self, 走査する傾きの正接: &[f32]) -> Option<f32> {
        let mut 最後の正接 = None;
        for &正接 in 走査する傾きの正接 {
            if self.分類と坂に沿った変位(正接).0 != 坂の箱の保持と滑走::保持 {
                return 最後の正接;
            }
            最後の正接 = Some(正接);
        }
        最後の正接
    }

    fn 走らせる条件(&self, 傾きの正接: f32) -> 坂の場面の条件 {
        坂の場面の条件 {
            傾きの正接,
            鉛直軸まわりの回し: 0.0,
            静止摩擦係数: 摩擦係数::生成する(0.6).unwrap(),
            動摩擦係数: 摩擦係数::生成する(0.2).unwrap(),
            下り向きの初速: 0.0,
            静止摩擦の解き方: 場面の静止摩擦の解き方::接触点集合の接線を同時に解く,
        }
    }
}
