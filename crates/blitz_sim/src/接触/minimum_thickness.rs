//! 形の最小の厚み: 接触に参加する形が最も薄い向きに持つ厚み(判断12)。深い初期重なりを解くときに、1細分で詰めてよい
//! 貫通の長さの上限としてこの値を使い、数細分に分けて回復させる。上限を置かないと、深く重なった形が1細分で弾き飛ぶ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断12: 非貫通は法線方向の片側のXPBD位置拘束であり、貫通しているときだけ効く」

use blitz_math::メートル;

use super::generation_error::接触拘束の生成エラー;

/// 形が最も薄い向きに持つ厚み。正の有限のメートルである。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 形の最小の厚み(メートル);

impl 形の最小の厚み {
    /// 0以下と非有限を型付きエラーで拒む。0の厚みは補正の上限を0にして接触が永久に解けなくなる。
    pub fn 生成する(厚み: メートル) -> Result<Self, 接触拘束の生成エラー> {
        if !厚み.値().is_finite() || 厚み.値() <= 0.0 {
            return Err(接触拘束の生成エラー::形の最小の厚みが値域の外 { 値: 厚み.値() });
        }
        Ok(Self(厚み))
    }

    /// 2つの形のうち薄い方の厚み。接触1点の上限は、触れ合う2つの形のうち薄い側が決める。
    pub fn 薄い方を選ぶ(self, 相手: Self) -> Self {
        if 相手.0 < self.0 { 相手 } else { self }
    }

    /// 厚みのメートル。
    pub fn 長さ(&self) -> メートル {
        self.0
    }
}
