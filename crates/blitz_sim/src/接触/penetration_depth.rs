//! 符号付き貫通量: 接触点1つで2つの形が食い込んでいる符号付きの長さを、剛体の解法が使う単精度で持つ型(判断11)。
//! 正は食い込み、0は接しているだけ、負は接触生成の余白の内側でその長さだけ離れていることを表す。
//! `blitz_collision` の符号付き貫通量は倍精度であり、単精度へ狭めるのは接触点を局所へ写すこの1箇所だけである(未決定の事項5)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断11: 接触拘束は接触点集合から細分ごとに生成する一時のバッチであり、参加者の組ごとに別のバッチを持ち、座標系の写しは剛体の側が行う」

use blitz_math::メートル;

/// 接触点1つで2つの形が食い込んでいる符号付きの長さ。負はその長さだけ離れていることを表す。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 符号付き貫通量(メートル);

impl 符号付き貫通量 {
    // 狭める境界だけが作る。接触生成の余白の内側であることは倍精度の側の型が保証しており、狭めた結果の有限性は境界が確かめる。
    pub(super) fn 検査済みの長さから組む(長さ: メートル) -> Self {
        Self(長さ)
    }

    /// 食い込んでいる符号付きの長さ。
    pub fn 長さ(&self) -> メートル {
        self.0
    }
}
