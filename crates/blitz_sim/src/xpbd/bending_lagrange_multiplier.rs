//! 曲げ拘束のラグランジュ乗数。1つの角の拘束が一刻みの反復の間に累積する補正の総量であり、単位はキログラム平方メートル(ラジアン・キログラム平方メートル)である。
//! 距離拘束の乗数(キログラム・メートル)と次元が違うため別の型で持つ。逆慣性(毎キログラム平方メートル)を掛けると角(ラジアン)になり、
//! 逆質量(毎キログラム)を掛けると平方メートルになって、勾配(毎メートル)に掛けて自由度へ加える補正の変位になる。
//! 寿命は呼び出し側が持つ。物理刻みの開始時に`零()`から始め、反復ごとに更新後の値を次の反復へ渡す(判断5)。

use std::ops::{Add, Mul, Sub};

use blitz_math::{ラジアン, 平方メートル, 逆キログラム, 逆キログラム平方メートル};

/// キログラム平方メートル単位の曲げのラグランジュ乗数。符号は任意であり、静止角より曲がった拘束を戻す向きの補正で負になる。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 曲げのラグランジュ乗数(f32);

impl 曲げのラグランジュ乗数 {
    /// 物理刻みの開始時の値。
    pub fn 零() -> Self {
        Self(0.0)
    }

    /// 角を逆慣性で割った量。反復の式のΔλ = (−C − α̃λ) ÷ (有効逆慣性 + α̃)がこの形である。
    /// 前提: 逆慣性は正である(有効逆慣性が0の拘束は射影の前に退化として除かれる)。
    pub fn 角を逆慣性で割って生成する(角: ラジアン, 逆慣性: 逆キログラム平方メートル) -> Self {
        Self(角.値() / 逆慣性.値())
    }

    /// 境界向けの生値取り出し。ドメインAPI内部では使わない。
    pub fn 値(&self) -> f32 {
        self.0
    }
}

impl Add for 曲げのラグランジュ乗数 {
    type Output = Self;
    fn add(self, 右辺: Self) -> Self {
        Self(self.0 + 右辺.0)
    }
}

impl Sub for 曲げのラグランジュ乗数 {
    type Output = Self;
    fn sub(self, 右辺: Self) -> Self {
        Self(self.0 - 右辺.0)
    }
}

/// 次元の合成: 乗数 × 逆慣性 = 角。反復の式のα̃λの項である。
impl Mul<逆キログラム平方メートル> for 曲げのラグランジュ乗数 {
    type Output = ラジアン;
    fn mul(self, 逆慣性: 逆キログラム平方メートル) -> ラジアン {
        ラジアン::生成する(self.0 * 逆慣性.値())
    }
}

/// 次元の合成: 乗数 × 逆質量 = 平方メートル。勾配(毎メートル)に掛けて補正の変位になる。
impl Mul<逆キログラム> for 曲げのラグランジュ乗数 {
    type Output = 平方メートル;
    fn mul(self, 逆質量: 逆キログラム) -> 平方メートル {
        平方メートル::生成する(self.0 * 逆質量.値())
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn 逆慣性で割って作り逆慣性を掛けると角へ戻り逆質量を掛けると平方メートルになる() {
        let 逆慣性 = 逆キログラム平方メートル::生成する(4.0).unwrap();
        let 乗数 = 曲げのラグランジュ乗数::角を逆慣性で割って生成する(ラジアン::生成する(-2.0), 逆慣性);
        assert_eq!(乗数, 曲げのラグランジュ乗数(-0.5));
        assert_eq!(乗数 * 逆慣性, ラジアン::生成する(-2.0));
        assert_eq!(乗数 * 逆キログラム::生成する(2.0).unwrap(), 平方メートル::生成する(-1.0));
        assert_eq!(乗数 + 曲げのラグランジュ乗数::零() - 乗数, 曲げのラグランジュ乗数::零());
    }
}
