//! 目標拘束を一回射影した結果。補正できた枝と、射影できない理由の枝を同じ型で返し、呼び出し側が区別できるようにする。
//! 退化を黙って補正0で返さないのは、逆質量0の粒子への目標拘束や目標に達した拘束が反復の中で無言に無視される状態を型で見えるようにするためである。

use blitz_math::{ワールド, 変位};

use super::lagrange_multiplier::ラグランジュ乗数;

/// 目標拘束の一回の射影の結果。射影できない枝ではラグランジュ乗数は変わらず、呼び出し側は渡した値をそのまま次の反復へ持ち越す。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 目標拘束の一回の射影の結果 {
    /// 補正を求めた。呼び出し側が`位置.変位を足す(補正)`で粒子の位置を更新し、更新後のラグランジュ乗数を次の反復へ渡す。
    補正した {
        補正: 変位<ワールド>,
        更新後のラグランジュ乗数: ラグランジュ乗数,
    },
    /// 粒子の逆質量が0であり、動かせない。
    粒子が固定,
    /// 粒子が目標と一致していて、補正の向きが定まらない(拘束は満たされている)。
    目標と一致している,
}
