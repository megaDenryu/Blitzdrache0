//! XPBDの曲げ拘束の正典式(判断1・判断11)の共通部。角のスカラー拘束を1回反復するときに、線(3点の折れ角)と面(4点の二面角)が共有する計算である。
//! CPUの参照計算であり、GPUの実装(`shaders/xpbd_bending_projection.slang`)はこの符号・単位・演算の順で書く。
//!
//! 記号と単位の規約(点iはワールドの位置[メートル]、wiはその逆質量[毎キログラム]):
//!   θ    = 現在の角                        [ラジアン]  測り方は線と面で違う(`bending_line_projection`・`bending_surface_projection`)
//!   C    = (θ − 静止角)を最短の弧へ畳んだ角  [ラジアン]  静止角より曲がっていれば正
//!   g_i  = ∂θ ÷ ∂x_i                       [毎メートル] 各参加点の勾配。総和は0(平行移動で角は変わらない)
//!   W    = Σ w_i |g_i|²                     [毎キログラム平方メートル] 有効逆慣性
//!   α̃    = 曲げのコンプライアンス ÷ 刻み幅²   [毎キログラム平方メートル] 刻み依存量。刻みの開始時に1度だけ導く
//!   Δλ   = (−C − α̃ λ) ÷ (W + α̃)            [キログラム平方メートル]
//!   λ    ← λ + Δλ                           [キログラム平方メートル]
//!   補正_i = w_i Δλ g_i                      [メートル]
//! 退化(全て固定・線分や辺が潰れている・曲げの面が定まらない)は非数を作らずに理由の枝を返し、λは変えない。
//! 参照: `_doc/設計/XPBD共通拘束基盤.md`「判断11」、`_doc/計画/ユビキタス言語.md`「XPBD共通拘束基盤の語彙」。

use blitz_math::{ラジアン, 逆キログラム平方メートル};

use super::bending_lagrange_multiplier::曲げのラグランジュ乗数;
use super::rest_angle::静止角;

/// 曲げ拘束を1つの刻み幅で解くときの係数。静止角と刻み依存量を持ち、その刻みの全反復で同じ値を使う。
/// 線の射影(`線を一回射影する`)と面の射影(`面を一回射影する`)はこの型のメソッドであり、角と勾配の測り方だけが違う。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 曲げ拘束の一刻みの係数 {
    静止角: 静止角,
    刻み依存量: 逆キログラム平方メートル,
}

impl 曲げ拘束の一刻みの係数 {
    pub(super) fn 生成する(静止角: 静止角, 刻み依存量: 逆キログラム平方メートル) -> Self {
        Self { 静止角, 刻み依存量 }
    }

    pub fn 静止角(&self) -> 静止角 {
        self.静止角
    }

    /// 拘束違反 C = θ − 静止角 を、−πからπまでの最短の弧へ畳んだ角。
    pub(super) fn 拘束違反(&self, 角: ラジアン) -> ラジアン {
        (角 - self.静止角.値()).一周の中で最短の弧へ畳む()
    }

    /// 正典式の乗数の増分 Δλ = (−C − α̃λ) ÷ (W + α̃)。
    /// 前提: 有効逆慣性は正である(全て固定の退化は呼び出し側が先に除く)。
    pub(super) fn 乗数の増分を求める(
        &self,
        拘束違反: ラジアン,
        有効逆慣性: 逆キログラム平方メートル,
        乗数: 曲げのラグランジュ乗数,
    ) -> 曲げのラグランジュ乗数 {
        曲げのラグランジュ乗数::角を逆慣性で割って生成する(
            (拘束違反 + 乗数 * self.刻み依存量) * -1.0,
            有効逆慣性 + self.刻み依存量,
        )
    }
}
