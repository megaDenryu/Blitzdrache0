//! 片端を留めた線(16点・間隔0.05メートル・1点0.01キログラム)を重力で垂らす検査(Issue #38「検証シーン」の線)。
//! 曲げのコンプライアンスを変えるとロープ状(先端が真下まで垂れる)から棒寄り(先端が留めた端の高さに近い)へ変わること、硬い距離拘束の伸びは変わらないことを見る。
//! `--nocapture`で走らせると、曲げのコンプライアンス別・刻み幅別・反復回数別の先端の垂れと折れ角の分布の表を出す(`_doc/計測/布の曲げ拘束_2026-09-02.md`の線の記録の材料)。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, メートル毎秒毎秒, 変位, 秒, 逆キログラム};

use super::bending_line_reference_harness::留めた線の参照計算;
use super::bending_test_fixtures::曲げの係数;
use super::distance_projection_test_fixtures::係数 as 距離の係数;

const 点数: usize = 16;
const 間隔: f32 = 0.05;
const 逆質量: f32 = 100.0;
const 重力: f32 = 9.8;
const 経過時間の秒: u32 = 4;
const コンプライアンスの候補: [f32; 5] = [0.0, 0.01, 0.1, 1.0, 10.0];
/// (刻み幅の分母, 反復回数)の組。反復を増やした列は、硬い曲げの効き方が反復の収束で決まることを見るための列である。
const 条件の候補: [(u32, u32); 7] = [(60, 4), (60, 8), (60, 16), (60, 64), (60, 256), (120, 4), (120, 8)];
/// 硬さの差を読む反復回数。反復4回では硬い曲げも柔らかい曲げも未収束で同じ垂れになる(表の1列目)。
const 硬さを読む反復回数: u32 = 256;

/// 線を経過時間だけ進めた後の観測: 先端の垂れ(留めた端の高さからの下がり)・折れ角の二乗平均平方根・最大の折れ角・最大の伸び。
struct 線の観測 {
    先端の垂れ: f32,
    折れ角の二乗平均平方根: f32,
    最大の折れ角: f32,
    最大の伸び: f32,
}

fn 線を垂らす(コンプライアンス: f32, 刻み幅の分母: u32, 反復回数: u32) -> 線の観測 {
    let 刻み幅の秒 = 1.0 / f32::from(u16::try_from(刻み幅の分母).unwrap());
    let 落下 = メートル毎秒毎秒::生成する(-重力) * 秒::生成する(刻み幅の秒) * 秒::生成する(刻み幅の秒);
    let mut 線 = 留めた線の参照計算::生成する(
        点数,
        メートル::生成する(間隔),
        逆キログラム::生成する(逆質量).unwrap(),
        距離の係数(間隔, 0.0, 刻み幅の秒),
        曲げの係数(0.0, コンプライアンス, 刻み幅の秒),
        変位::成分から生成する(メートル::生成する(0.0), 落下, メートル::生成する(0.0)),
        0.99,
    );
    for _ in 0..経過時間の秒 * 刻み幅の分母 {
        線.一刻み進める(反復回数);
    }
    let 折れ角一覧 = 線.折れ角一覧();
    let 本数 = f32::from(u16::try_from(折れ角一覧.len()).unwrap());
    線の観測 {
        先端の垂れ: -線.先端().y().値(),
        折れ角の二乗平均平方根: (折れ角一覧.iter().map(|角| 角 * 角).sum::<f32>() / 本数).sqrt(),
        最大の折れ角: 折れ角一覧.iter().copied().fold(0.0, f32::max),
        最大の伸び: 線.最大の伸び(メートル::生成する(間隔)),
    }
}

#[test]
fn 曲げのコンプライアンスを小さくするほど先端の垂れと折れ角が減り硬い距離拘束の伸びは変わらない() {
    println!("線の曲げ: 曲げのコンプライアンス 刻み幅の分母 反復回数 先端の垂れ 折れ角の二乗平均平方根 最大の折れ角 最大の伸び");
    let mut 前の垂れ = -1.0f32;
    for コンプライアンス in コンプライアンスの候補 {
        for (刻み幅の分母, 反復回数) in 条件の候補 {
            let 観測 = 線を垂らす(コンプライアンス, 刻み幅の分母, 反復回数);
            println!(
                "線の曲げ: {コンプライアンス:.2e} {刻み幅の分母} {反復回数} {:.4e} {:.4e} {:.4e} {:.4e}",
                観測.先端の垂れ, 観測.折れ角の二乗平均平方根, 観測.最大の折れ角, 観測.最大の伸び
            );
        }
        let 観測 = 線を垂らす(コンプライアンス, 60, 硬さを読む反復回数);
        assert!(
            観測.先端の垂れ > 前の垂れ,
            "コンプライアンス{コンプライアンス}で垂れ{}が前{前の垂れ}より小さい",
            観測.先端の垂れ
        );
        assert!(
            観測.最大の伸び < 0.02 * 間隔,
            "コンプライアンス{コンプライアンス}で伸び{}",
            観測.最大の伸び
        );
        前の垂れ = 観測.先端の垂れ;
    }
    let (棒寄り, ロープ状) = (線を垂らす(0.0, 60, 硬さを読む反復回数), 線を垂らす(10.0, 60, 硬さを読む反復回数));
    assert!(棒寄り.先端の垂れ < 0.5 * 間隔 * 15.0, "棒寄りの先端の垂れ{}", 棒寄り.先端の垂れ);
    assert!(ロープ状.先端の垂れ > 0.9 * 間隔 * 14.0, "ロープ状の先端の垂れ{}", ロープ状.先端の垂れ);
    assert!(棒寄り.折れ角の二乗平均平方根 < ロープ状.折れ角の二乗平均平方根 * 0.5);
}
