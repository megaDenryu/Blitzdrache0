//! 距離拘束のラグランジュ乗数。1つの拘束が一刻みの反復の間に累積する補正の総量であり、単位はキログラム・メートルである。
//! 逆質量(毎キログラム)を掛けると長さ(メートル)になり、それが自由度へ加える補正の長さである。
//! 寿命は呼び出し側が持つ。物理刻みの開始時に`零()`から始め、反復ごとに更新後の値を次の反復へ渡す(判断5)。

use std::ops::{Add, Mul, Sub};

use blitz_math::{キログラムメートル, メートル, 逆キログラム};

/// キログラム・メートル単位のラグランジュ乗数。符号は任意であり、伸びた距離拘束を縮める向きの補正で負になる。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct ラグランジュ乗数(f32);

impl ラグランジュ乗数 {
    /// 物理刻みの開始時の値。
    pub fn 零() -> Self {
        Self(0.0)
    }

    /// 長さを逆質量で割った量。反復の式のΔλ = (−C − α̃λ) ÷ (有効逆質量 + α̃)がこの形である。
    /// 前提: 逆質量は正である(有効逆質量が0の拘束は射影の前に退化として除かれる)。
    pub fn 長さを逆質量で割って生成する(長さ: メートル, 逆質量: 逆キログラム) -> Self {
        Self(長さ.値() / 逆質量.値())
    }

    /// 区間の中へ切り詰めた乗数。片側拘束(接触の非貫通・可動限界)が乗数の符号と1細分の補正の量を制限するときに使う。
    /// 前提: 下限は上限以下である(逆に渡すと下限を返す)。
    pub fn 区間へ収める(self, 下限: Self, 上限: Self) -> Self {
        if self < 下限 {
            return 下限;
        }
        if self > 上限 { 上限 } else { self }
    }

    /// 零で下から抑えた乗数。片側拘束が1細分に詰めた長さを単調に数えるとき、負の増分をこの形で0として扱う。
    pub fn 正の部分(self) -> Self {
        if self.0 > 0.0 { self } else { Self(0.0) }
    }

    /// 無次元の比で伸ばした乗数。同時に更新する方式が増分へ緩和係数を掛けるときに使う。
    pub fn 比で伸ばす(self, 比: f32) -> Self {
        Self(self.0 * 比)
    }

    /// 3つの成分を持つ乗数のベクトルの大きさ √(x² + y² + z²)。接線の乗数がクーロン円錐の判定に読む(判断13)。
    /// 3つの入力は座標軸の成分として対等であるため、レシーバを持たない関連関数である。
    pub fn 三成分の大きさを求める(x: Self, y: Self, z: Self) -> Self {
        Self((x.0 * x.0 + y.0 * y.0 + z.0 * z.0).sqrt())
    }

    /// 姿勢自由度の逆慣性テンソルが腕と向きの外積に掛ける大きさ。単位はこの乗数そのもの(キログラムメートル)である。
    pub fn キログラムメートル(&self) -> キログラムメートル {
        キログラムメートル::生成する(self.0)
    }

    /// 有効逆質量で割った長さとして既に求まっている実数を乗数として読む(単位はキログラム・メートル)。
    /// 接触点集合の法線の連立は行列を型の内側へ閉じて単位の無い実数で解くため、その結果を型へ戻す口がこれである。
    pub(crate) fn 有効逆質量で割った長さから生成する(値: f32) -> Self {
        Self(値)
    }

    /// 境界向けの生値取り出し。ドメインAPI内部では使わない。
    pub fn 値(&self) -> f32 {
        self.0
    }
}

impl Add for ラグランジュ乗数 {
    type Output = Self;
    fn add(self, 右辺: Self) -> Self {
        Self(self.0 + 右辺.0)
    }
}

impl Sub for ラグランジュ乗数 {
    type Output = Self;
    fn sub(self, 右辺: Self) -> Self {
        Self(self.0 - 右辺.0)
    }
}

/// 次元の合成: ラグランジュ乗数 × 逆質量 = 長さ。
impl Mul<逆キログラム> for ラグランジュ乗数 {
    type Output = メートル;
    fn mul(self, 逆質量: 逆キログラム) -> メートル {
        メートル::生成する(self.0 * 逆質量.値())
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn 逆質量で割って作り逆質量を掛けると長さへ戻る() {
        let 逆質量 = 逆キログラム::生成する(0.5).unwrap();
        let 乗数 = ラグランジュ乗数::長さを逆質量で割って生成する(メートル::生成する(-2.0), 逆質量);
        assert_eq!(乗数, ラグランジュ乗数(-4.0));
        assert_eq!(乗数 * 逆質量, メートル::生成する(-2.0));
        assert_eq!(乗数 + ラグランジュ乗数::零(), 乗数);
    }
}
