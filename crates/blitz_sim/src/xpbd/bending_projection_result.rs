//! 曲げ拘束を一回射影した結果。補正できた枝と、射影できない理由の枝を同じ型で返し、呼び出し側が区別できるようにする。
//! 退化を黙って補正0で返さないのは、潰れた線分や三角形の拘束が反復の中で無言に無視される状態を型で見えるようにするためである。
//! 線(3点)と面(4点)は補正の数が違うため別の型である。理由の枝ではラグランジュ乗数は変わらず、呼び出し側は渡した値をそのまま次の反復へ持ち越す。

use blitz_math::{ワールド, 変位};

use super::bending_lagrange_multiplier::曲げのラグランジュ乗数;

/// 線の曲げ拘束(3点の折れ角)の一回の射影の結果。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 線の曲げ拘束の一回の射影の結果 {
    /// 補正を求めた。呼び出し側が`位置.変位を足す(補正)`で3点の位置を更新し、更新後のラグランジュ乗数を次の反復へ渡す。
    補正した {
        補正0: 変位<ワールド>,
        補正1: 変位<ワールド>,
        補正2: 変位<ワールド>,
        更新後のラグランジュ乗数: 曲げのラグランジュ乗数,
    },
    /// 3点の逆質量が全て0であり、どれも動かせない。
    全て固定,
    /// 2つの線分のどちらかの長さが下限未満で、折れ角が定まらない。
    線分が潰れている,
    /// 2つの線分が一直線上にあり、曲げの面(補正の向き)が定まらない。静止角0なら拘束は満たされている。
    曲げの面が定まらない,
}

/// 面の曲げ拘束(共有する辺の2点と翼の2点の二面角)の一回の射影の結果。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 面の曲げ拘束の一回の射影の結果 {
    /// 補正を求めた。呼び出し側が`位置.変位を足す(補正)`で4点の位置を更新し、更新後のラグランジュ乗数を次の反復へ渡す。
    補正した {
        補正a: 変位<ワールド>,
        補正b: 変位<ワールド>,
        補正c: 変位<ワールド>,
        補正d: 変位<ワールド>,
        更新後のラグランジュ乗数: 曲げのラグランジュ乗数,
    },
    /// 4点の逆質量が全て0であり、どれも動かせない。
    全て固定,
    /// 共有する辺の長さが下限未満で、辺の向きが定まらない。
    辺が潰れている,
    /// どちらかの三角形の面積が下限未満で、法線が定まらない。
    三角形が潰れている,
}
