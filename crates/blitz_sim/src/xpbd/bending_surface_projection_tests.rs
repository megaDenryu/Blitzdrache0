//! 面の曲げ拘束の正典式の性質の検査(Issue #38の検証): 平らな4点で二面角が0であること・翼を法線の側へ折ると正であること・勾配が数値微分と一致し
//! 総和が0であること・硬い曲げが折れた面を静止角へ収束させること。退化の検査は`bending_surface_degeneracy_tests`が持つ。材料は`bending_test_fixtures`が持つ。

#![allow(clippy::unwrap_used)]

use blitz_math::{ワールド, 位置, 平方メートル, 角の勾配};

use super::bending_lagrange_multiplier::曲げのラグランジュ乗数;
