use super::bending_test_fixtures::{
    ワールドの位置を生成する, 勾配が数値微分と一致することを確かめる, 参加点, 曲げの係数
};
use super::distance_constraint_participant::距離拘束の参加点;

/// 共有する辺をx軸に置き、翼cを+y側、翼dを−y側に置いた4点。翼の高さを与えると法線(+z)の側へ折れる。
pub(super) fn 四点(翼cの高さ: f32, 翼dの高さ: f32) -> [位置<ワールド>; 4] {
    [
        ワールドの位置を生成する(0.0, 0.0, 0.0),
        ワールドの位置を生成する(1.0, 0.0, 0.0),
        ワールドの位置を生成する(0.5, 1.0, 翼cの高さ),
        ワールドの位置を生成する(0.5, -1.0, 翼dの高さ),
    ]
}

fn 二面角(点: &[位置<ワールド>]) -> f32 {
    二面角の幾何::位置から測る(点[0], 点[1], 点[2], 点[3]).unwrap().二面角().値()
}

#[test]
fn 平らで零で翼を法線の側へ折ると正で直角に折ると四分の一周になる() {
    assert_eq!(二面角(&四点(0.0, 0.0)), 0.0);
    assert!(二面角(&四点(0.1, 0.0)) > 0.0);
    assert!(二面角(&四点(0.0, 0.1)) > 0.0);
    assert!(二面角(&四点(-0.1, 0.0)) < 0.0);
    let 直角 = 二面角(&[
        ワールドの位置を生成する(0.0, 0.0, 0.0),
        ワールドの位置を生成する(1.0, 0.0, 0.0),
        ワールドの位置を生成する(0.5, 1.0, 0.0),
        ワールドの位置を生成する(0.5, 0.0, 1.0),
    ]);
    assert!((直角 - std::f32::consts::FRAC_PI_2).abs() < 1.0e-6, "直角の二面角{直角}");
}

#[test]
fn 勾配は数値微分と一致し総和は零で平らな面でも特異でない() {
    for 点一覧 in [四点(0.0, 0.0), 四点(0.3, -0.2), 四点(0.7, 0.4)] {
        let 幾何 = 二面角の幾何::位置から測る(点一覧[0], 点一覧[1], 点一覧[2], 点一覧[3]).unwrap();
        勾配が数値微分と一致することを確かめる(&点一覧, &幾何.勾配(), 二面角);
        let 総和 = 幾何.勾配().iter().fold(角の勾配::零(), |和, 勾配| 和 + *勾配) * 平方メートル::生成する(1.0);
        assert!(総和.長さ().値() < 1.0e-6, "勾配の総和{総和:?}");
    }
}

pub(super) fn 参加点一覧(点一覧: [位置<ワールド>; 4], 逆質量: f32) -> [距離拘束の参加点; 4] {
    [
        参加点(点一覧[0], 逆質量),
        参加点(点一覧[1], 逆質量),
        参加点(点一覧[2], 逆質量),
        参加点(点一覧[3], 逆質量),
    ]
}

/// 反証: 勾配の符号を反転すると、折れた面は静止角から離れる向きへ動く。
#[test]
fn 硬い曲げは折れた面を静止角へ収束させ乗数は補正の総量を表す() {
    for 静止角 in [0.0f32, 0.4] {
        let 係数 = 曲げの係数(静止角, 0.0, 1.0 / 60.0);
        let mut 点 = 参加点一覧(四点(0.6, 0.6), 1.0);
        let mut 乗数 = 曲げのラグランジュ乗数::零();
        for _ in 0..40 {
            match 係数.面を一回射影する(点[0], 点[1], 点[2], 点[3], 乗数) {
                面の曲げ拘束の一回の射影の結果::補正した {
                    補正a,
                    補正b,
                    補正c,
                    補正d,
                    更新後のラグランジュ乗数,
                } => {
                    点[0].位置 = 点[0].位置.変位を足す(補正a);
                    点[1].位置 = 点[1].位置.変位を足す(補正b);
                    点[2].位置 = 点[2].位置.変位を足す(補正c);
                    点[3].位置 = 点[3].位置.変位を足す(補正d);
                    乗数 = 更新後のラグランジュ乗数;
                }
                退化 => panic!("退化の枝に入った: {退化:?}"),
            }
        }
        let 角 = 二面角(&[点[0].位置, 点[1].位置, 点[2].位置, 点[3].位置]);
        assert!((角 - 静止角).abs() < 1.0e-3, "静止角{静止角}に対して二面角{角}");
        assert!(乗数.値() < 0.0);
    }
}
