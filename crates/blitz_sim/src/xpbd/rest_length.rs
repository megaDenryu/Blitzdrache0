//! 距離拘束が保とうとする2点の距離。0以上の有限のメートルだけを持つ。
//! メートルをそのまま受けないのは、負の静止長には満たせる距離が無く(反復が収束しない)、非有限の静止長は拘束違反から補正と乗数までを非数にするためであり、その検査を生成の1箇所へ閉じる。
//! 参照: `_doc/設計/XPBD共通拘束基盤.md`「距離拘束の符号と単位の規約」。

use blitz_math::メートル;
use thiserror::Error;

/// 距離拘束の静止長。生成が0以上の有限値であることを保証する。0は2点の一致を求める拘束として許す。
#[derive(Debug, Clone, Copy, PartialEq)]
#[repr(transparent)]
pub struct 静止長(メートル);

impl 静止長 {
    /// 負と非有限を型付きエラーで拒む。
    pub fn 生成する(長さ: メートル) -> Result<Self, 静止長エラー> {
        if !長さ.値().is_finite() {
            return Err(静止長エラー::非有限値 { 長さ });
        }
        if 長さ.値() < 0.0 {
            return Err(静止長エラー::負の値 { 長さ });
        }
        Ok(Self(長さ))
    }

    /// 長さとしての値。正典式が拘束違反 C = |d| − 静止長 を作るときに読む。
    pub fn 値(&self) -> メートル {
        self.0
    }
}

/// 静止長の生成が拒んだ入力。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 静止長エラー {
    #[error("静止長は有限値でなければならない(指定値: {長さ:?})")]
    非有限値 { 長さ: メートル },
    #[error("静止長は0以上でなければならない(指定値: {長さ:?})")]
    負の値 { 長さ: メートル },
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 零と正の有限値だけを通す() {
        assert_eq!(
            静止長::生成する(メートル::生成する(0.0)).map(|生成した| 生成した.値()),
            Ok(メートル::生成する(0.0))
        );
        assert!(静止長::生成する(メートル::生成する(1.5)).is_ok());
        assert_eq!(
            静止長::生成する(メートル::生成する(-1.0)),
            Err(静止長エラー::負の値 {
                長さ: メートル::生成する(-1.0)
            })
        );
        assert!(matches!(
            静止長::生成する(メートル::生成する(f32::NAN)),
            Err(静止長エラー::非有限値 { .. })
        ));
        assert!(matches!(
            静止長::生成する(メートル::生成する(f32::INFINITY)),
            Err(静止長エラー::非有限値 { .. })
        ));
        assert!(matches!(
            静止長::生成する(メートル::生成する(f32::NEG_INFINITY)),
            Err(静止長エラー::非有限値 { .. })
        ));
    }
}
