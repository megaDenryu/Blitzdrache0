//! XPBDの距離拘束の正典式(判断1)。CPUの参照計算であり、GPUの実装はこの符号・単位・演算の順で書く(判断2・判断7)。
//!
//! 記号と単位の規約(a・bは参加点、wa・wbはその逆質量[毎キログラム]、位置はワールド[メートル]):
//!   d  = b − a                       [メートル]  aからbへ向かう差
//!   n  = d ÷ |d|                     [無次元]    aからbへ向かう単位向き
//!   C  = |d| − 静止長                 [メートル]  拘束違反。伸びていれば正
//!   α̃  = コンプライアンス ÷ 刻み幅²   [毎キログラム] 刻み依存量。刻みの開始時に1度だけ導く
//!   Δλ = (−C − α̃ λ) ÷ (wa + wb + α̃) [キログラム・メートル] 伸びていれば負
//!   λ  ← λ + Δλ                      [キログラム・メートル]
//!   補正a = −wa Δλ n、補正b = +wb Δλ n [メートル]  伸びていればaはbの側へ、bはaの側へ寄る
//! 有効逆質量は wa + wb である(距離拘束の勾配は単位向きであり、勾配の2乗は1)。
//! 退化の2つ(両方の逆質量が0・2点が一致)は非数を作らずに理由の枝を返し、λは変えない。
//!
//! 参照: `_doc/設計/XPBD共通拘束基盤.md`「判断1」「判断5」、`_doc/計画/ユビキタス言語.md`「XPBD共通拘束基盤の語彙」。

use blitz_math::{メートル, 逆キログラム};

use super::distance_constraint_participant::距離拘束の参加点;
use super::distance_projection_result::距離拘束の一回の射影の結果;
use super::lagrange_multiplier::ラグランジュ乗数;
use super::rest_length::静止長;

/// 2点の距離の下限の値(メートル)。裸の数で置くのは、面の曲げのGPUの写し(`shaders/xpbd_bending_projection.slang`)が同じ綴りの定数を持ち、`cargo xtask conform`が値を突き合わせるためである。
const 向きが定まる最小の距離のメートル: f32 = 1.0e-6;

/// 2点の距離がこれより短いと単位向きを作らない。GPUの布(`shaders/cloth_constraint.slang`)が距離の2乗に置く下限1e-12と同じ長さである。
pub(super) const 向きが定まる最小の距離: メートル = メートル::生成する(向きが定まる最小の距離のメートル);

/// 距離拘束を1つの刻み幅で解くときの係数。静止長と刻み依存量を持ち、その刻みの全反復で同じ値を使う。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 距離拘束の一刻みの係数 {
    静止長: 静止長,
    刻み依存量: 逆キログラム,
}

impl 距離拘束の一刻みの係数 {
    pub(super) fn 生成する(静止長: 静止長, 刻み依存量: 逆キログラム) -> Self {
        Self { 静止長, 刻み依存量 }
    }

    /// 正典式の1回の反復。呼び出し側は補正を位置へ足し、更新後のラグランジュ乗数を次の反復へ渡す。
    pub fn 一回射影する(
        &self, a: 距離拘束の参加点, b: 距離拘束の参加点, 乗数: ラグランジュ乗数
    ) -> 距離拘束の一回の射影の結果 {
        let 有効逆質量 = a.逆質量 + b.逆質量;
        if 有効逆質量.零か() {
            return 距離拘束の一回の射影の結果::両方が固定;
        }
        let 差 = b.位置 - a.位置;
        let 距離 = 差.長さ();
        if 距離 < 向きが定まる最小の距離 {
            return 距離拘束の一回の射影の結果::向きが定まらない;
        }
        let 拘束違反 = 距離 - self.静止長.値();
        let 乗数の増分 = ラグランジュ乗数::長さを逆質量で割って生成する(
            (拘束違反 + 乗数 * self.刻み依存量) * -1.0,
            有効逆質量 + self.刻み依存量,
        );
        距離拘束の一回の射影の結果::補正した {
            補正a: 差.長さを付け替える(乗数の増分 * a.逆質量 * -1.0),
            補正b: 差.長さを付け替える(乗数の増分 * b.逆質量),
            更新後のラグランジュ乗数: 乗数 + 乗数の増分,
        }
    }
}
