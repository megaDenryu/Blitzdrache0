//! 曲げ拘束の検査が共有する部品: ワールドの位置と参加点の組み立て・一刻みの係数の組み立て・勾配の数値微分・
//! 3点の線を距離拘束(硬い)と曲げ拘束で準静的に垂らす器。線の検査と面の検査の両方がこれを読む。

use blitz_math::{メートル, ラジアン, ワールド, 位置, 平方メートル, 秒, 角の勾配, 逆キログラム};

use super::bending_canonical_projection::曲げ拘束の一刻みの係数;
use super::bending_compliance::曲げのコンプライアンス;
use super::bending_constraint_parameters::曲げ拘束の引数;
use super::distance_constraint_participant::距離拘束の参加点;
use super::rest_angle::静止角;
use super::time_step_width::刻み幅;

pub(super) fn ワールドの位置を生成する(x: f32, y: f32, z: f32) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

pub(super) fn 参加点(位置: 位置<ワールド>, 逆質量: f32) -> 距離拘束の参加点 {
    let 逆質量 = match 逆キログラム::生成する(逆質量) {
        Ok(逆質量) => 逆質量,
        Err(エラー) => panic!("検査の逆質量を作れない: {エラー}"),
    };
    距離拘束の参加点::生成する(位置, 逆質量)
}

pub(super) fn 曲げの係数(静止角の値: f32, コンプライアンス: f32, 刻み幅の秒: f32) -> 曲げ拘束の一刻みの係数 {
    let 静止角 = match 静止角::生成する(ラジアン::生成する(静止角の値)) {
        Ok(静止角) => 静止角,
        Err(エラー) => panic!("検査の静止角を作れない: {エラー}"),
    };
    let コンプライアンス = match 曲げのコンプライアンス::生成する(コンプライアンス) {
        Ok(コンプライアンス) => コンプライアンス,
        Err(エラー) => panic!("検査の曲げのコンプライアンスを作れない: {エラー}"),
    };
    let 刻み幅 = match 刻み幅::生成する(秒::生成する(刻み幅の秒)) {
        Ok(刻み幅) => 刻み幅,
        Err(エラー) => panic!("検査の刻み幅を作れない: {エラー}"),
    };
    match 曲げ拘束の引数::生成する(静止角, コンプライアンス).刻み幅で解く係数を導く(刻み幅) {
        Ok(係数) => 係数,
        Err(エラー) => panic!("検査の係数を導けない: {エラー}"),
    }
}

/// 勾配の3成分。勾配に1平方メートルを掛けた変位の成分がそのままの値である。
pub(super) fn 勾配の成分(勾配: 角の勾配<ワールド>) -> [f32; 3] {
    let 変位 = 勾配 * 平方メートル::生成する(1.0);
    [変位.x().値(), 変位.y().値(), 変位.z().値()]
}

/// 位置の1成分を刻みぶん動かした位置。数値微分が読む。
pub(super) fn 成分をずらす(位置: 位置<ワールド>, 成分: usize, 刻み: f32) -> 位置<ワールド> {
    let mut 成分一覧 = [位置.x().値(), 位置.y().値(), 位置.z().値()];
    成分一覧[成分] += 刻み;
    ワールドの位置を生成する(成分一覧[0], 成分一覧[1], 成分一覧[2])
}

/// 角を測る関数を中央差分で微分し、勾配の各成分と突き合わせる。
pub(super) fn 勾配が数値微分と一致することを確かめる(
    点一覧: &[位置<ワールド>],
    勾配一覧: &[角の勾配<ワールド>],
    角を測る: impl Fn(&[位置<ワールド>]) -> f32,
) {
    let 刻み = 1.0e-3;
    for (点の番号, 勾配) in 勾配一覧.iter().enumerate() {
        let 解析 = 勾配の成分(*勾配);
        for (成分, 解析の成分) in 解析.iter().enumerate() {
            let mut 前 = 点一覧.to_vec();
            let mut 後 = 点一覧.to_vec();
            前[点の番号] = 成分をずらす(点一覧[点の番号], 成分, -刻み);
            後[点の番号] = 成分をずらす(点一覧[点の番号], 成分, 刻み);
            let 数値 = (角を測る(&後) - 角を測る(&前)) / (2.0 * 刻み);
            assert!(
                (数値 - 解析の成分).abs() < 2.0e-3,
                "点{点の番号}の成分{成分}: 数値微分{数値}に対して勾配{解析の成分}"
            );
        }
    }
}
