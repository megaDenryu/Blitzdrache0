//! 片端を留めた線(ロープ)を重力で垂らす検査用の器(Issue #38「検証シーン」の線)。線状物理のドメイン型(Issue #9)はまだ無いため、
//! 距離拘束(硬い)と線の曲げ拘束を同じ反復へ混ぜたCPUの参照計算をここが回す。先頭の2点を留める(留めた端の向きを持つ片持ち)のは、
//! 1点だけを留めると曲げ拘束が端の向きを決められず、線全体が硬さに依らず垂直へ回ってしまうためである。
//! 速度は位置と前の位置の差(ベルレ形)で持ち、布の参照計算と同じ減衰を掛ける。工程は積分→乗数の零化→(距離拘束→曲げ拘束)×反復回数である。
//! 先端・折れ角・伸びの観測の口は`bending_line_reference_observation`が持つ。

use blitz_math::{メートル, ワールド, 位置, 変位, 逆キログラム};

use super::bending_canonical_projection::曲げ拘束の一刻みの係数;
use super::bending_lagrange_multiplier::曲げのラグランジュ乗数;
use super::bending_projection_result::線の曲げ拘束の一回の射影の結果;
use super::distance_canonical_projection::距離拘束の一刻みの係数;
use super::distance_constraint_participant::距離拘束の参加点;
use super::distance_projection_result::距離拘束の一回の射影の結果;
use super::lagrange_multiplier::ラグランジュ乗数;

pub(super) struct 留めた線の参照計算 {
    pub(super) 位置一覧: Vec<位置<ワールド>>,
    前の位置一覧: Vec<位置<ワールド>>,
    逆質量一覧: Vec<逆キログラム>,
    距離の係数: 距離拘束の一刻みの係数,
    曲げの係数: 曲げ拘束の一刻みの係数,
    一刻みの落下: 変位<ワールド>,
    速度減衰: f32,
}

impl 留めた線の参照計算 {
    /// x軸に沿って間隔ぶんずつ並べた点数の線。先頭2点の逆質量は0(留めた端)である。
    pub(super) fn 生成する(
        点数: usize,
        間隔: メートル,
        逆質量: 逆キログラム,
        距離の係数: 距離拘束の一刻みの係数,
        曲げの係数: 曲げ拘束の一刻みの係数,
        一刻みの落下: 変位<ワールド>,
        速度減衰: f32,
    ) -> Self {
        let 位置一覧: Vec<位置<ワールド>> = (0..点数)
            .map(|番号| 位置::生成する(間隔 * 番号を実数へ変換する(番号), メートル::生成する(0.0), メートル::生成する(0.0)))
            .collect();
        Self {
            前の位置一覧: 位置一覧.clone(),
            逆質量一覧: (0..点数).map(|番号| if 番号 < 2 { 逆キログラム::零() } else { 逆質量 }).collect(),
            位置一覧,
            距離の係数,
            曲げの係数,
            一刻みの落下,
            速度減衰,
        }
    }

    pub(super) fn 一刻み進める(&mut self, 反復回数: u32) {
        for 番号 in 0..self.位置一覧.len() {
            let 今 = self.位置一覧[番号];
            let 移動 = (今 - self.前の位置一覧[番号]).比で伸ばす(self.速度減衰);
            self.前の位置一覧[番号] = 今;
            if !self.逆質量一覧[番号].零か() {
                self.位置一覧[番号] = 今.変位を足す(移動 + self.一刻みの落下);
            }
        }
        let mut 距離の乗数一覧 = vec![ラグランジュ乗数::零(); self.位置一覧.len() - 1];
        let mut 曲げの乗数一覧 = vec![曲げのラグランジュ乗数::零(); self.位置一覧.len().saturating_sub(2)];
        for _ in 0..反復回数 {
            for (番号, 乗数) in 距離の乗数一覧.iter_mut().enumerate() {
                self.距離拘束を射影する(番号, 乗数);
            }
            for (番号, 乗数) in 曲げの乗数一覧.iter_mut().enumerate() {
                self.曲げ拘束を射影する(番号, 乗数);
            }
        }
    }

    fn 参加点(&self, 番号: usize) -> 距離拘束の参加点 {
        距離拘束の参加点::生成する(self.位置一覧[番号], self.逆質量一覧[番号])
    }

    fn 距離拘束を射影する(&mut self, 番号: usize, 乗数: &mut ラグランジュ乗数) {
        if let 距離拘束の一回の射影の結果::補正した {
            補正a,
            補正b,
            更新後のラグランジュ乗数,
        } = self.距離の係数.一回射影する(self.参加点(番号), self.参加点(番号 + 1), *乗数)
        {
            *乗数 = 更新後のラグランジュ乗数;
            self.位置一覧[番号] = self.位置一覧[番号].変位を足す(補正a);
            self.位置一覧[番号 + 1] = self.位置一覧[番号 + 1].変位を足す(補正b);
        }
    }

    fn 曲げ拘束を射影する(&mut self, 番号: usize, 乗数: &mut 曲げのラグランジュ乗数) {
        if let 線の曲げ拘束の一回の射影の結果::補正した {
            補正0,
            補正1,
            補正2,
            更新後のラグランジュ乗数,
        } = self
            .曲げの係数
            .線を一回射影する(self.参加点(番号), self.参加点(番号 + 1), self.参加点(番号 + 2), *乗数)
        {
            *乗数 = 更新後のラグランジュ乗数;
            for (点, 補正) in [補正0, 補正1, 補正2].into_iter().enumerate() {
                self.位置一覧[番号 + 点] = self.位置一覧[番号 + 点].変位を足す(補正);
            }
        }
    }
}

fn 番号を実数へ変換する(番号: usize) -> f32 {
    f32::from(u16::try_from(番号).unwrap_or_else(|_| panic!("点の番号がu16に収まらない: {番号}")))
}
