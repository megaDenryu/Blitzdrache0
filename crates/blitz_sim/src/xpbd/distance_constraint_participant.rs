//! 距離拘束に参加する点自由度の、射影が読む2つの量。位置はワールドのメートル、逆質量は毎キログラム(固定した自由度は0)である。
//! 速度を持たないのは、射影が位置と重みだけを読むためである(判断3の点自由度から射影に要る分だけを写す)。

use blitz_math::{ワールド, 位置, 逆キログラム};

/// 距離拘束の片側の参加点。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 距離拘束の参加点 {
    /// ワールドの位置。反復の途中では直前の反復の補正を足した位置を渡す。
    pub 位置: 位置<ワールド>,
    /// 逆質量。0なら射影がこの点を動かさない。
    pub 逆質量: 逆キログラム,
}

impl 距離拘束の参加点 {
    pub fn 生成する(位置: 位置<ワールド>, 逆質量: 逆キログラム) -> Self {
        Self { 位置, 逆質量 }
    }
}
