//! 距離拘束の検査が共有する部品: x軸上の参加点の組み立て・一刻みの係数の組み立て・反復を回して距離と乗数を測る器。
//! 正典式の性質の検査と退化の検査の両方がこれを読む。

use blitz_math::{メートル, ワールド, 位置, 秒, 逆キログラム};

use super::compliance::コンプライアンス;
use super::distance_canonical_projection::距離拘束の一刻みの係数;
use super::distance_constraint_parameters::距離拘束の引数;
use super::distance_constraint_participant::距離拘束の参加点;
use super::distance_projection_result::距離拘束の一回の射影の結果;
use super::lagrange_multiplier::ラグランジュ乗数;
use super::time_step_width::刻み幅;

/// x軸上の点。逆質量0は固定した点を表す。
pub(super) fn 点(x: f32, 逆質量: f32) -> 距離拘束の参加点 {
    let 位置 = 位置::<ワールド>::生成する(メートル::生成する(x), メートル::生成する(0.0), メートル::生成する(0.0));
    let 逆質量 = match 逆キログラム::生成する(逆質量) {
        Ok(逆質量) => 逆質量,
        Err(エラー) => panic!("検査の逆質量を作れない: {エラー}"),
    };
    距離拘束の参加点::生成する(位置, 逆質量)
}

pub(super) fn 係数(静止長: f32, コンプライアンス: f32, 刻み幅の秒: f32) -> 距離拘束の一刻みの係数 {
    let コンプライアンス = match コンプライアンス::生成する(コンプライアンス) {
        Ok(コンプライアンス) => コンプライアンス,
        Err(エラー) => panic!("検査のコンプライアンスを作れない: {エラー}"),
    };
    let 刻み幅 = match 刻み幅::生成する(秒::生成する(刻み幅の秒)) {
        Ok(刻み幅) => 刻み幅,
        Err(エラー) => panic!("検査の刻み幅を作れない: {エラー}"),
    };
    match 距離拘束の引数::生成する(メートル::生成する(静止長), コンプライアンス).刻み幅で解く係数を導く(刻み幅)
    {
        Ok(係数) => 係数,
        Err(エラー) => panic!("検査の係数を導けない: {エラー}"),
    }
}

/// 反復を回し、最後の距離と乗数を返す。呼び出し側が更新後の乗数を次の反復へ渡す形の実例である。
pub(super) fn 反復して距離と乗数を測る(
    係数: &距離拘束の一刻みの係数,
    mut a: 距離拘束の参加点,
    mut b: 距離拘束の参加点,
    回数: usize,
) -> (メートル, ラグランジュ乗数) {
    let mut 乗数 = ラグランジュ乗数::零();
    for _ in 0..回数 {
        match 係数.一回射影する(a, b, 乗数) {
            距離拘束の一回の射影の結果::補正した {
                補正a,
                補正b,
                更新後のラグランジュ乗数,
            } => {
                a.位置 = a.位置.変位を足す(補正a);
                b.位置 = b.位置.変位を足す(補正b);
                乗数 = 更新後のラグランジュ乗数;
            }
            退化 => panic!("退化の枝に入った: {退化:?}"),
        }
    }
    ((b.位置 - a.位置).長さ(), 乗数)
}
