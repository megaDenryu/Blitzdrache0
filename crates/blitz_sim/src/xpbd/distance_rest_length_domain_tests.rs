//! 静止長の定義域の検査(Issue #34のレビュー是正): 負と非有限の静止長が生成で拒まれること。
//! 各検査の生成が通った枝は、検査を外したときに何が起きるかを示すためのものであり、検査が在る限り到達しない。
//! 静止長の検査を外して実測した結果: 負の静止長では硬い拘束を8回反復しても距離が静止長に到達せず(距離1で振動する)、非数の静止長では補正と乗数が非数になる。

use blitz_math::メートル;

use super::distance_projection_result::距離拘束の一回の射影の結果;
use super::distance_projection_test_fixtures::{反復して距離と乗数を測る, 検査済みの静止長で係数を作る, 点};
use super::lagrange_multiplier::ラグランジュ乗数;
use super::rest_length::{静止長, 静止長エラー};

#[test]
fn 負の静止長は生成で拒まれ拒まれなければ硬い拘束が静止長へ収束しない() {
    match 静止長::生成する(メートル::生成する(-1.0)) {
        Err(エラー) => assert_eq!(
            エラー,
            静止長エラー::負の値 {
                長さ: メートル::生成する(-1.0)
            }
        ),
        Ok(静止長) => {
            let 係数 = 検査済みの静止長で係数を作る(静止長, 0.0, 1.0 / 60.0);
            let (距離, _) = 反復して距離と乗数を測る(&係数, 点(0.0, 1.0), 点(2.0, 1.0), 8);
            assert!(
                (距離.値() - 静止長.値().値()).abs() < 1.0e-5,
                "距離{}が静止長{:?}に到達しない",
                距離.値(),
                静止長
            );
        }
    }
}

#[test]
fn 非数の静止長は生成で拒まれ拒まれなければ補正と乗数が非数になる() {
    match 静止長::生成する(メートル::生成する(f32::NAN)) {
        Err(エラー) => assert!(matches!(エラー, 静止長エラー::非有限値 { .. })),
        Ok(静止長) => {
            let 係数 = 検査済みの静止長で係数を作る(静止長, 0.0, 1.0 / 60.0);
            match 係数.一回射影する(点(0.0, 1.0), 点(2.0, 1.0), ラグランジュ乗数::零()) {
                距離拘束の一回の射影の結果::補正した {
                    補正a,
                    補正b,
                    更新後のラグランジュ乗数,
                } => {
                    assert!(補正a.x().値().is_finite(), "補正a{:?}が非数", 補正a);
                    assert!(補正b.x().値().is_finite(), "補正b{:?}が非数", 補正b);
                    assert!(更新後のラグランジュ乗数.値().is_finite(), "乗数{:?}が非数", 更新後のラグランジュ乗数);
                }
                退化 => panic!("退化の枝に入った: {退化:?}"),
            }
        }
    }
}

#[test]
fn 無限の静止長は生成で拒まれる() {
    for 長さ in [f32::INFINITY, f32::NEG_INFINITY] {
        assert!(matches!(静止長::生成する(メートル::生成する(長さ)), Err(静止長エラー::非有限値 { .. })));
    }
}
