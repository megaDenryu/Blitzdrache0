//! 面の曲げ拘束: 共有する辺の2点(a・b)と翼の2点(c・d)が作る2つの三角形の二面角の測り方と勾配、およびその一回の射影(判断11の面の定式化)。
//! `曲げ拘束の一刻みの係数`のうち面の幾何だけに触れる工程であり、線の折れ角(`bending_line_projection`)と分ける。
//!
//! 記号(x_a・x_bは共有する辺、x_cは三角形(a, b, c)の翼、x_dは三角形(b, a, d)の翼):
//!   E  = x_b − x_a、ê = E ÷ |E|                     共有する辺の向き
//!   N1 = (x_a − x_c) × (x_b − x_c)、n1 = N1 ÷ |N1|  三角形(a, b, c)の法線(|N1|は面積の2倍)
//!   N2 = (x_b − x_d) × (x_a − x_d)、n2 = N2 ÷ |N2|  三角形(b, a, d)の法線。平らな面では n1 = n2
//!   θ  = atan2(ê · (n2 × n1), n1 · n2)              二面角。平らで0、翼が両方とも法線の側へ折れると正。符号は4点の並びで決まる
//!   g_c = |E| n1 ÷ |N1|、g_d = |E| n2 ÷ |N2|
//!   g_a = ((x_c − x_b)·ê) n1 ÷ |N1| + ((x_d − x_b)·ê) n2 ÷ |N2|
//!   g_b = −((x_c − x_a)·ê) n1 ÷ |N1| − ((x_d − x_a)·ê) n2 ÷ |N2|
//! 勾配は角の余弦の微分(1 ÷ sinθ)を経由しない形であり、平らな面(θ = 0)でも特異でない。総和は0である。
//! 退化: |E|が下限未満(辺が潰れている)、|N1|か|N2|が下限未満(三角形が潰れている)。θ = ±πの折り畳みは弧の畳みで扱う。

use blitz_math::{ラジアン, ワールド, 位置, 平方メートル, 角の勾配, 逆キログラム平方メートル};

use super::bending_canonical_projection::曲げ拘束の一刻みの係数;
use super::bending_lagrange_multiplier::曲げのラグランジュ乗数;
use super::bending_projection_result::面の曲げ拘束の一回の射影の結果;
use super::distance_canonical_projection::向きが定まる最小の距離;
use super::distance_constraint_participant::距離拘束の参加点;

// 三角形の面積ベクトルの長さの下限の値(平方メートル)。裸の数で置くのは、GPUの写し(`shaders/xpbd_bending_projection.slang`)が同じ綴りの定数を持ち、`cargo xtask conform`が値を突き合わせるためである。
const 面が定まる最小の面積の平方メートル: f32 = 1.0e-12;

// 三角形の面積ベクトルの長さ(面積の2倍)がこれより小さいと法線を作らない。辺の下限1e-6メートルの2乗である。
const 面が定まる最小の面積: 平方メートル = 平方メートル::生成する(面が定まる最小の面積の平方メートル);

/// 二面角とその勾配。角の測り方の正本であり、拘束の射影と、静止角の計測と、面の検査が読む曲率の分布がこれを使う。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 二面角の幾何 {
    二面角: ラジアン,
    勾配a: 角の勾配<ワールド>,
    勾配b: 角の勾配<ワールド>,
    勾配c: 角の勾配<ワールド>,
    勾配d: 角の勾配<ワールド>,
}

impl 二面角の幾何 {
    /// 4点の位置から二面角と勾配を測る。退化は理由の枝で返す。
    pub fn 位置から測る(
        辺a: 位置<ワールド>,
        辺b: 位置<ワールド>,
        翼c: 位置<ワールド>,
        翼d: 位置<ワールド>,
    ) -> Result<Self, 面の曲げ拘束の一回の射影の結果> {
        let 辺 = 辺b - 辺a;
        let 辺の長さ = 辺.長さ();
        if 辺の長さ < 向きが定まる最小の距離 {
            return Err(面の曲げ拘束の一回の射影の結果::辺が潰れている);
        }
        let (面積1, 面積2) = ((辺a - 翼c).外積(&(辺b - 翼c)), (辺b - 翼d).外積(&(辺a - 翼d)));
        if 面積1.長さ() < 面が定まる最小の面積 || 面積2.長さ() < 面が定まる最小の面積 {
            return Err(面の曲げ拘束の一回の射影の結果::三角形が潰れている);
        }
        let (Ok(辺の向き), Ok(法線1), Ok(法線2)) = (辺.単位方向(), 面積1.単位方向(), 面積2.単位方向()) else {
            return Err(面の曲げ拘束の一回の射影の結果::三角形が潰れている);
        };
        let 勾配c = 角の勾配::方向へ生成する(法線1, 辺の長さ / 面積1.長さ());
        let 勾配d = 角の勾配::方向へ生成する(法線2, 辺の長さ / 面積2.長さ());
        let 勾配a = 角の勾配::方向へ生成する(法線1, (翼c - 辺b).方向に沿う長さ(辺の向き) / 面積1.長さ())
            + 角の勾配::方向へ生成する(法線2, (翼d - 辺b).方向に沿う長さ(辺の向き) / 面積2.長さ());
        let 勾配b = -(角の勾配::方向へ生成する(法線1, (翼c - 辺a).方向に沿う長さ(辺の向き) / 面積1.長さ())
            + 角の勾配::方向へ生成する(法線2, (翼d - 辺a).方向に沿う長さ(辺の向き) / 面積2.長さ()));
        Ok(Self {
            二面角: ラジアン::生成する(辺の向き.三重積(&法線2, &法線1).atan2(法線1.内積(&法線2))),
            勾配a,
            勾配b,
            勾配c,
            勾配d,
        })
    }

    pub fn 二面角(&self) -> ラジアン {
        self.二面角
    }

    /// 4点の勾配を辺a・辺b・翼c・翼dの順で返す。検査が数値微分と突き合わせるために読む。
    pub fn 勾配(&self) -> [角の勾配<ワールド>; 4] {
        [self.勾配a, self.勾配b, self.勾配c, self.勾配d]
    }
}

impl 曲げ拘束の一刻みの係数 {
    /// 面の曲げ拘束の正典式の1回の反復。呼び出し側は補正を4点の位置へ足し、更新後のラグランジュ乗数を次の反復へ渡す。
    /// 参加点の型は距離拘束と共有する(射影が読むのは位置と逆質量という同じ2つの量である)。
    pub fn 面を一回射影する(
        &self,
        辺a: 距離拘束の参加点,
        辺b: 距離拘束の参加点,
        翼c: 距離拘束の参加点,
        翼d: 距離拘束の参加点,
        乗数: 曲げのラグランジュ乗数,
    ) -> 面の曲げ拘束の一回の射影の結果 {
        if (辺a.逆質量 + 辺b.逆質量 + 翼c.逆質量 + 翼d.逆質量).零か() {
            return 面の曲げ拘束の一回の射影の結果::全て固定;
        }
        let 幾何 = match 二面角の幾何::位置から測る(辺a.位置, 辺b.位置, 翼c.位置, 翼d.位置) {
            Ok(幾何) => 幾何,
            Err(退化) => return 退化,
        };
        let 有効逆慣性 = 幾何.勾配a.逆質量で重み付けた2乗の大きさ(辺a.逆質量)
            + 幾何.勾配b.逆質量で重み付けた2乗の大きさ(辺b.逆質量)
            + 幾何.勾配c.逆質量で重み付けた2乗の大きさ(翼c.逆質量)
            + 幾何.勾配d.逆質量で重み付けた2乗の大きさ(翼d.逆質量);
        if 有効逆慣性 == 逆キログラム平方メートル::零() {
            return 面の曲げ拘束の一回の射影の結果::全て固定;
        }
        let 増分 = self.乗数の増分を求める(self.拘束違反(幾何.二面角), 有効逆慣性, 乗数);
        面の曲げ拘束の一回の射影の結果::補正した {
            補正a: 幾何.勾配a * (増分 * 辺a.逆質量),
            補正b: 幾何.勾配b * (増分 * 辺b.逆質量),
            補正c: 幾何.勾配c * (増分 * 翼c.逆質量),
            補正d: 幾何.勾配d * (増分 * 翼d.逆質量),
            更新後のラグランジュ乗数: 乗数 + 増分,
        }
    }
}
