//! 目標拘束の静的な引数(判断4の3区分のうち静的な引数)。コンプライアンスだけを持ち、刻み幅を受けて一刻みの係数を導く。
//! 静止長を持たないのは、目標拘束が「点を外から与えた目標位置へ一致させる」拘束であり、正典式では静止長0の距離拘束と同じ形になるためである
//! (`_doc/設計/XPBD共通拘束基盤.md`「判断6」)。目標位置は静的な引数でなく毎刻み与える入力であるため、ここには持たない。

use super::compliance::{コンプライアンス, コンプライアンスエラー};
use super::target_canonical_projection::目標拘束の一刻みの係数;
use super::time_step_width::刻み幅;

/// 目標拘束の静的な引数。参加する点の添字も目標位置も持たない(添字はバッチが、目標位置は毎刻みの入力が持つ)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 目標拘束の引数 {
    /// 拘束の柔らかさ。0で硬い接続、正で柔らかい追従。
    pub コンプライアンス: コンプライアンス,
}

impl 目標拘束の引数 {
    /// 検査済みのコンプライアンスを包む。
    pub fn 生成する(コンプライアンス: コンプライアンス) -> Self {
        Self { コンプライアンス }
    }

    /// 硬い接続(世界固定点と、硬いアタッチ)。
    pub fn 硬い() -> Self {
        Self::生成する(コンプライアンス::硬い())
    }

    /// この刻み幅で反復に使う係数。物理刻みの開始時に1度だけ呼び、その刻みの全反復で同じ係数を使う(判断8の工程6)。
    pub fn 刻み幅で解く係数を導く(
        &self, 刻み幅: 刻み幅
    ) -> Result<目標拘束の一刻みの係数, コンプライアンスエラー> {
        Ok(目標拘束の一刻みの係数::生成する(self.コンプライアンス.刻み依存量(刻み幅)?))
    }
}
