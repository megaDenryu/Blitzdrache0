//! XPBDの目標拘束の正典式(判断6)。点自由度を外から与えた目標位置へ一致させる拘束であり、式は目標側の逆質量を0とした静止長0の距離拘束そのものである。
//!
//! 記号と単位の規約(xは粒子の位置、wはその逆質量[毎キログラム]、目標はワールド[メートル]):
//!   d  = 目標 − x                   [メートル]  粒子から目標へ向かう差
//!   n  = d ÷ |d|                     [無次元]    粒子から目標へ向かう単位向き
//!   C  = |d|                         [メートル]  拘束違反。離れていれば正
//!   Δλ = (−C − α̃ λ) ÷ (w + α̃)       [キログラム・メートル] 離れていれば負
//!   補正 = −w Δλ n                   [メートル]  粒子が目標の側へ寄る
//! 距離拘束の正典式(`distance_canonical_projection`)へ静止長0と逆質量0の目標を渡して解き、式をここへ再び書かない。
//! GPUの写しも同じ`projectDistance`(`shaders/xpbd_projection.slang`)を目標側の逆質量0で読む。
//! 退化の2つ(粒子の逆質量が0・粒子が目標と一致)は非数を作らずに理由の枝を返し、λは変えない。
//! 世界固定点は目標を刻みを跨いで動かさない特別な場合であり、別の族を作らない。

use blitz_math::{ワールド, 位置, 逆キログラム};

use super::distance_canonical_projection::距離拘束の一刻みの係数;
use super::distance_constraint_participant::距離拘束の参加点;
use super::distance_projection_result::距離拘束の一回の射影の結果;
use super::lagrange_multiplier::ラグランジュ乗数;
use super::rest_length::静止長;
use super::target_projection_result::目標拘束の一回の射影の結果;

/// 目標拘束を1つの刻み幅で解くときの係数。刻み依存量を静止長0の距離拘束の係数として持ち、その刻みの全反復で同じ値を使う。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 目標拘束の一刻みの係数 {
    静止長零の距離の係数: 距離拘束の一刻みの係数,
}

impl 目標拘束の一刻みの係数 {
    pub(super) fn 生成する(刻み依存量: 逆キログラム) -> Self {
        Self {
            静止長零の距離の係数: 距離拘束の一刻みの係数::生成する(静止長::零(), 刻み依存量),
        }
    }

    /// 正典式の1回の反復。呼び出し側は補正を粒子の位置へ足し、更新後のラグランジュ乗数を次の反復へ渡す。
    pub fn 一回射影する(
        &self,
        粒子: 距離拘束の参加点,
        目標位置: 位置<ワールド>,
        乗数: ラグランジュ乗数,
    ) -> 目標拘束の一回の射影の結果 {
        let 目標 = 距離拘束の参加点::生成する(目標位置, 逆キログラム::零());
        match self.静止長零の距離の係数.一回射影する(粒子, 目標, 乗数) {
            距離拘束の一回の射影の結果::補正した {
                補正a,
                更新後のラグランジュ乗数,
                ..
            } => 目標拘束の一回の射影の結果::補正した {
                補正: 補正a,
                更新後のラグランジュ乗数,
            },
            距離拘束の一回の射影の結果::両方が固定 => 目標拘束の一回の射影の結果::粒子が固定,
            距離拘束の一回の射影の結果::向きが定まらない => 目標拘束の一回の射影の結果::目標と一致している,
        }
    }
}
