//! 距離拘束の静的な引数(判断4の3区分のうち静的な引数)。静止長とコンプライアンスを持ち、刻み幅を受けて一刻みの係数を導く。
//! 静止長とコンプライアンスはどちらも生成で定義域を検査した型であるため、この型の生成は失敗しない。

use super::compliance::{コンプライアンス, コンプライアンスエラー};
use super::distance_canonical_projection::距離拘束の一刻みの係数;
use super::rest_length::静止長;
use super::time_step_width::刻み幅;

/// 距離拘束の静的な引数。参加点の添字は持たない(参加点は射影のたびに位置と逆質量として渡す)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 距離拘束の引数 {
    /// 拘束が保とうとする2点の距離。0以上の有限値であることを型が保証する。
    pub 静止長: 静止長,
    /// 拘束の柔らかさ。0で硬い拘束。
    pub コンプライアンス: コンプライアンス,
}

impl 距離拘束の引数 {
    /// 検査済みの静止長とコンプライアンスを束ねる。
    pub fn 生成する(静止長: 静止長, コンプライアンス: コンプライアンス) -> Self {
        Self {
            静止長, コンプライアンス
        }
    }

    /// この刻み幅で反復に使う係数。物理刻みの開始時に1度だけ呼び、その刻みの全反復で同じ係数を使う(判断8の工程6)。
    pub fn 刻み幅で解く係数を導く(
        &self, 刻み幅: 刻み幅
    ) -> Result<距離拘束の一刻みの係数, コンプライアンスエラー> {
        Ok(距離拘束の一刻みの係数::生成する(
            self.静止長,
            self.コンプライアンス.刻み依存量(刻み幅)?,
        ))
    }
}
