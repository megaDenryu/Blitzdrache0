//! 曲げ拘束が保とうとする角(線では2つの線分の折れ角、面では隣接する2つの三角形の二面角)。−πからπまでの有限のラジアンだけを持つ。
//! ラジアンをそのまま受けないのは、非有限の静止角が拘束違反から補正と乗数までを非数にし、半周を越える静止角は最短の弧へ畳んだ拘束違反と
//! 一致しないためであり、その検査を生成の1箇所へ閉じる。塑性(静止角の書き換え)はこの型の値を差し替えることで接続する(Issue #38の完了条件)。

use blitz_math::ラジアン;
use thiserror::Error;

/// 曲げ拘束の静止角。生成が−πからπまでの有限値であることを保証する。線の折れ角は0が真っ直ぐ、面の二面角は0が平らである。
#[derive(Debug, Clone, Copy, PartialEq)]
#[repr(transparent)]
pub struct 静止角(ラジアン);

impl 静止角 {
    /// 非有限と、半周を越える角を型付きエラーで拒む。
    pub fn 生成する(角: ラジアン) -> Result<Self, 静止角エラー> {
        if !角.値().is_finite() {
            return Err(静止角エラー::非有限値 { 角 });
        }
        if 角.値().abs() > std::f32::consts::PI {
            return Err(静止角エラー::半周を越える { 角 });
        }
        Ok(Self(角))
    }

    /// 真っ直ぐな線と平らな面の静止角。
    pub fn 零() -> Self {
        Self(ラジアン::生成する(0.0))
    }

    /// 角としての値。正典式が拘束違反 C = 角 − 静止角 を作るときに読む。
    pub fn 値(&self) -> ラジアン {
        self.0
    }
}

/// 静止角の生成が拒んだ入力。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 静止角エラー {
    #[error("静止角は有限値でなければならない(指定値: {角:?})")]
    非有限値 { 角: ラジアン },
    #[error("静止角は−πからπまででなければならない(指定値: {角:?})")]
    半周を越える { 角: ラジアン },
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 半周までの有限の角だけを通す() {
        assert_eq!(静止角::零().値(), ラジアン::生成する(0.0));
        assert!(静止角::生成する(ラジアン::生成する(-std::f32::consts::PI)).is_ok());
        assert!(matches!(
            静止角::生成する(ラジアン::生成する(4.0)),
            Err(静止角エラー::半周を越える { .. })
        ));
        assert!(matches!(
            静止角::生成する(ラジアン::生成する(f32::NAN)),
            Err(静止角エラー::非有限値 { .. })
        ));
    }
}
