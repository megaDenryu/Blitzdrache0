//! 線の曲げ拘束: 3点の折れ角の測り方と勾配、およびその一回の射影(判断11の線の定式化)。
//! `曲げ拘束の一刻みの係数`のうち線の幾何だけに触れる工程であり、面の二面角(`bending_surface_projection`)と分ける。
//!
//! 記号(p0・p1・p2は3点、a = p1 − p0、b = p2 − p1は2つの線分の変位):
//!   φ  = aとbのなす角(折れ角)。真っ直ぐで0、折り返しでπ。符号は持たない(3次元の線には基準の面が無く、Issue #39の姿勢自由度が担う)
//!   m  = (a × b) ÷ |a × b|  曲げの面の単位法線
//!   u_a = m × â、u_b = m × b̂  各線分に直交し曲げの面に沿う単位向き(u_aはbの側、u_bはaから離れる側)
//!   g0 = +u_a ÷ |a|、g2 = +u_b ÷ |b|、g1 = −g0 − g2
//! 退化: |a|か|b|が下限未満(線分が潰れている)、sinφ = |a × b| ÷ (|a||b|)が下限未満(曲げの面が定まらない)。

use blitz_math::{ラジアン, ワールド, 位置, 角の勾配, 逆キログラム平方メートル, 逆メートル};

use super::bending_canonical_projection::曲げ拘束の一刻みの係数;
use super::bending_lagrange_multiplier::曲げのラグランジュ乗数;
use super::bending_projection_result::線の曲げ拘束の一回の射影の結果;
use super::distance_canonical_projection::向きが定まる最小の距離;
use super::distance_constraint_participant::距離拘束の参加点;

// 2つの線分のなす角の正弦がこれより小さいと、曲げの面(補正の向き)を作らない。
const 曲げの面が定まる最小の正弦: f32 = 1.0e-6;

/// 3点の折れ角とその勾配。角の測り方の正本であり、拘束の射影と、線の検査が読む曲率の分布の両方がこれを使う。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 線の折れ角の幾何 {
    折れ角: ラジアン,
    勾配0: 角の勾配<ワールド>,
    勾配1: 角の勾配<ワールド>,
    勾配2: 角の勾配<ワールド>,
}

impl 線の折れ角の幾何 {
    /// 3点の位置から折れ角と勾配を測る。退化は理由の枝で返す。
    pub fn 位置から測る(
        p0: 位置<ワールド>,
        p1: 位置<ワールド>,
        p2: 位置<ワールド>,
    ) -> Result<Self, 線の曲げ拘束の一回の射影の結果> {
        let (a, b) = (p1 - p0, p2 - p1);
        let (長さa, 長さb) = (a.長さ(), b.長さ());
        if 長さa < 向きが定まる最小の距離 || 長さb < 向きが定まる最小の距離 {
            return Err(線の曲げ拘束の一回の射影の結果::線分が潰れている);
        }
        let 外積 = a.外積(&b);
        let 正弦 = 外積.長さ() / (長さa * 長さb);
        if 正弦 < 曲げの面が定まる最小の正弦 {
            return Err(線の曲げ拘束の一回の射影の結果::曲げの面が定まらない);
        }
        let (Ok(法線), Ok(向きa), Ok(向きb)) = (外積.単位方向(), a.単位方向(), b.単位方向()) else {
            return Err(線の曲げ拘束の一回の射影の結果::曲げの面が定まらない);
        };
        let (Ok(直交a), Ok(直交b)) = (法線.直交する方向を求める(&向きa), 法線.直交する方向を求める(&向きb)) else {
            return Err(線の曲げ拘束の一回の射影の結果::曲げの面が定まらない);
        };
        let 勾配0 = 角の勾配::方向へ生成する(直交a, 逆メートル::長さの逆数(長さa));
        let 勾配2 = 角の勾配::方向へ生成する(直交b, 逆メートル::長さの逆数(長さb));
        Ok(Self {
            折れ角: ラジアン::生成する(正弦.atan2(向きa.内積(&向きb))),
            勾配0,
            勾配1: -(勾配0 + 勾配2),
            勾配2,
        })
    }

    pub fn 折れ角(&self) -> ラジアン {
        self.折れ角
    }

    /// 3点の勾配を点の並びの順で返す。検査が数値微分と突き合わせるために読む。
    pub fn 勾配(&self) -> [角の勾配<ワールド>; 3] {
        [self.勾配0, self.勾配1, self.勾配2]
    }
}

impl 曲げ拘束の一刻みの係数 {
    /// 線の曲げ拘束の正典式の1回の反復。呼び出し側は補正を3点の位置へ足し、更新後のラグランジュ乗数を次の反復へ渡す。
    /// 参加点の型は距離拘束と共有する(射影が読むのは位置と逆質量という同じ2つの量である)。
    pub fn 線を一回射影する(
        &self,
        p0: 距離拘束の参加点,
        p1: 距離拘束の参加点,
        p2: 距離拘束の参加点,
        乗数: 曲げのラグランジュ乗数,
    ) -> 線の曲げ拘束の一回の射影の結果 {
        if (p0.逆質量 + p1.逆質量 + p2.逆質量).零か() {
            return 線の曲げ拘束の一回の射影の結果::全て固定;
        }
        let 幾何 = match 線の折れ角の幾何::位置から測る(p0.位置, p1.位置, p2.位置) {
            Ok(幾何) => 幾何,
            Err(退化) => return 退化,
        };
        let 有効逆慣性 = 幾何.勾配0.逆質量で重み付けた2乗の大きさ(p0.逆質量)
            + 幾何.勾配1.逆質量で重み付けた2乗の大きさ(p1.逆質量)
            + 幾何.勾配2.逆質量で重み付けた2乗の大きさ(p2.逆質量);
        if 有効逆慣性 == 逆キログラム平方メートル::零() {
            return 線の曲げ拘束の一回の射影の結果::全て固定;
        }
        let 増分 = self.乗数の増分を求める(self.拘束違反(幾何.折れ角), 有効逆慣性, 乗数);
        線の曲げ拘束の一回の射影の結果::補正した {
            補正0: 幾何.勾配0 * (増分 * p0.逆質量),
            補正1: 幾何.勾配1 * (増分 * p1.逆質量),
            補正2: 幾何.勾配2 * (増分 * p2.逆質量),
            更新後のラグランジュ乗数: 乗数 + 増分,
        }
    }
}
