//! 曲げ拘束の柔らかさを表す物性の値。単位は毎ニュートンメートル(ラジアン毎ニュートンメートル。秒の2乗毎キログラム平方メートル)であり、
//! 0で硬い曲げ、正で有限の柔らかさになる。距離拘束のコンプライアンス(メートル毎ニュートン)とは次元が違うため別の型で持ち、
//! 伸びの物性を倍率で流用して曲げを表す経路を型で閉じる(Issue #38「拘束データ」)。
//! 参照: `_doc/設計/XPBD共通拘束基盤.md`「判断11」。

use blitz_math::逆キログラム平方メートル;
use thiserror::Error;

use super::time_step_width::刻み幅;

/// 毎ニュートンメートル単位の曲げのコンプライアンス。0以上の有限値だけを持つ。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 曲げのコンプライアンス(f32);

impl 曲げのコンプライアンス {
    /// 負と非有限を型付きエラーで拒む。0は硬い曲げとして許す。
    pub fn 生成する(値: f32) -> Result<Self, 曲げのコンプライアンスエラー> {
        if !値.is_finite() {
            return Err(曲げのコンプライアンスエラー::非有限値 { 値 });
        }
        if 値 < 0.0 {
            return Err(曲げのコンプライアンスエラー::負の値 { 値 });
        }
        Ok(Self(値))
    }

    /// 硬い曲げ。
    pub fn 硬い() -> Self {
        Self(0.0)
    }

    /// 反復の式に現れる刻み依存量 α̃ = コンプライアンス ÷ 刻み幅の2乗。次元は逆慣性と同じ(毎キログラム平方メートル)であり、有効逆慣性へそのまま足せる。
    /// 物理刻みの開始時に1度だけ導く(判断8の工程6)。単精度の表現範囲を超える組み合わせは型付きエラーで拒む。
    pub fn 刻み依存量(&self, 刻み幅: 刻み幅) -> Result<逆キログラム平方メートル, 曲げのコンプライアンスエラー> {
        let 刻み = 刻み幅.秒().値();
        let 値 = self.0 / (刻み * 刻み);
        逆キログラム平方メートル::生成する(値).map_err(|_| 曲げのコンプライアンスエラー::刻み依存量が範囲を外れた { 値 })
    }

    /// 境界向けの生値取り出し。ドメインAPI内部では使わない。
    pub fn 値(&self) -> f32 {
        self.0
    }
}

/// 曲げのコンプライアンスの生成が拒んだ入力。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 曲げのコンプライアンスエラー {
    #[error("曲げのコンプライアンスは有限値でなければならない(指定値: {値})")]
    非有限値 { 値: f32 },
    #[error("曲げのコンプライアンスは0以上でなければならない(指定値: {値})")]
    負の値 { 値: f32 },
    #[error("曲げのコンプライアンスを刻み幅の2乗で割った量が単精度の範囲を外れた(結果: {値})")]
    刻み依存量が範囲を外れた { 値: f32 },
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;
    use blitz_math::秒;

    #[test]
    fn 刻み依存量は刻み幅の2乗で割った量になり負と非有限は拒む() {
        let 刻み幅 = 刻み幅::生成する(秒::生成する(0.5)).unwrap();
        assert_eq!(
            曲げのコンプライアンス::生成する(0.5).unwrap().刻み依存量(刻み幅),
            Ok(逆キログラム平方メートル::生成する(2.0).unwrap())
        );
        assert!(曲げのコンプライアンス::硬い().刻み依存量(刻み幅).unwrap().零か());
        assert_eq!(
            曲げのコンプライアンス::生成する(-0.1),
            Err(曲げのコンプライアンスエラー::負の値 { 値: -0.1 })
        );
        assert!(matches!(
            曲げのコンプライアンス::生成する(f32::INFINITY),
            Err(曲げのコンプライアンスエラー::非有限値 { .. })
        ));
    }
}
