//! 刻み幅と反復回数を変えても同じコンプライアンスで定常の伸びが変わらないこと(Issue #34の検証)。
//! 対照として、旧式(過緩和係数と反復回数で硬さが決まる)では同じ条件で定常の伸びが桁で変わることを示す。
//! 解析解: 質量mの質点をばね定数k = 1 ÷ コンプライアンスのばねで吊ると、静的な釣り合いの伸びは m g ÷ k = g × コンプライアンス ÷ 逆質量である。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, メートル毎秒毎秒, 秒, 逆キログラム};

use super::compliance::コンプライアンス;
use super::hanging_mass_harness::吊り下げの検査;
use super::rest_length::静止長;
use super::time_step_width::刻み幅;

const 重力の大きさ: f32 = 9.8;
const 検査するコンプライアンス: f32 = 0.001;
const 検査する逆質量: f32 = 1.0;
const 刻み幅と反復回数の組: [(f32, usize); 3] = [(1.0 / 60.0, 1), (1.0 / 120.0, 4), (1.0 / 30.0, 2)];

fn 検査を組む(刻み幅の秒: f32, 反復回数: usize) -> 吊り下げの検査 {
    吊り下げの検査 {
        静止長: 静止長::生成する(メートル::生成する(1.0)).unwrap(),
        逆質量: 逆キログラム::生成する(検査する逆質量).unwrap(),
        重力: メートル毎秒毎秒::生成する(重力の大きさ),
        刻み幅: 刻み幅::生成する(秒::生成する(刻み幅の秒)).unwrap(),
        反復回数,
        刻み数: 400,
    }
}

#[test]
fn 正典式の定常の伸びは刻み幅と反復回数に依らず解析解に一致する() {
    let 解析解 = 重力の大きさ * 検査するコンプライアンス / 検査する逆質量;
    for (刻み幅の秒, 反復回数) in 刻み幅と反復回数の組 {
        let 伸び = 検査を組む(刻み幅の秒, 反復回数).正典式での定常の伸び(コンプライアンス::生成する(検査するコンプライアンス).unwrap());
        assert!(
            (伸び.値() - 解析解).abs() < 1.0e-5,
            "刻み幅{刻み幅の秒}秒・反復{反復回数}回の定常の伸び{}が解析解{解析解}から外れた",
            伸び.値()
        );
    }
}

#[test]
fn 旧式の定常の伸びは刻み幅と反復回数で桁が変わる() {
    let 過緩和係数 = 0.5;
    let 伸び一覧: Vec<f32> = 刻み幅と反復回数の組
        .iter()
        .map(|(刻み幅の秒, 反復回数)| 検査を組む(*刻み幅の秒, *反復回数).旧式での定常の伸び(過緩和係数).値())
        .collect();
    let 最大 = 伸び一覧.iter().copied().fold(f32::MIN, f32::max);
    let 最小 = 伸び一覧.iter().copied().fold(f32::MAX, f32::min);
    assert!(最小 > 0.0, "旧式でも吊った質点は伸びる: {伸び一覧:?}");
    assert!(最大 / 最小 > 10.0, "旧式の定常の伸びが条件で変わらなかった: {伸び一覧:?}");
}
