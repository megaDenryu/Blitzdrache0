//! 正典式の性質の検査(Issue #34の検証): 硬い拘束の収束・符号の規約・片方固定・柔らかい拘束の有限の柔らかさ・乗数の持ち越し。
//! 柔らかい拘束の解析解: 静止から1刻みの陰的オイラーのばね(k = 1 ÷ コンプライアンス)は、伸びC0をC0 × α̃ ÷ (wa + wb + α̃)へ縮める。

use blitz_math::メートル;

use super::distance_projection_result::距離拘束の一回の射影の結果;
use super::distance_projection_test_fixtures::{係数, 反復して距離と乗数を測る, 点};
use super::lagrange_multiplier::ラグランジュ乗数;

#[test]
fn 硬い拘束は静止長へ収束し乗数は縮めた量を逆質量で割った値になる() {
    let (距離, 乗数) = 反復して距離と乗数を測る(&係数(1.0, 0.0, 1.0 / 60.0), 点(0.0, 1.0), 点(2.0, 1.0), 4);
    assert!((距離.値() - 1.0).abs() < 1.0e-5, "距離{}", 距離.値());
    assert!((乗数.値() - (-0.5)).abs() < 1.0e-5, "乗数{}", 乗数.値());
}

#[test]
fn 伸びていればaはbの側へbはaの側へ等しく寄る() {
    match 係数(1.0, 0.0, 1.0 / 60.0).一回射影する(点(0.0, 1.0), 点(2.0, 1.0), ラグランジュ乗数::零()) {
        距離拘束の一回の射影の結果::補正した { 補正a, 補正b, .. } => {
            assert!((補正a.x().値() - 0.5).abs() < 1.0e-5);
            assert!((補正b.x().値() + 0.5).abs() < 1.0e-5);
            assert_eq!((補正a.y(), 補正a.z()), (メートル::生成する(0.0), メートル::生成する(0.0)));
        }
        退化 => panic!("退化の枝に入った: {退化:?}"),
    }
}

#[test]
fn 片方が固定なら補正は全てもう片方に載る() {
    match 係数(1.0, 0.0, 1.0 / 60.0).一回射影する(点(0.0, 0.0), 点(2.0, 1.0), ラグランジュ乗数::零()) {
        距離拘束の一回の射影の結果::補正した { 補正a, 補正b, .. } => {
            assert!(補正a.零か());
            assert!((補正b.x().値() + 1.0).abs() < 1.0e-5);
        }
        退化 => panic!("退化の枝に入った: {退化:?}"),
    }
}

#[test]
fn 柔らかい拘束は有限の柔らかさで解析解の残りの伸びへ収束する() {
    let (距離, _) = 反復して距離と乗数を測る(&係数(1.0, 0.01, 0.1), 点(0.0, 1.0), 点(2.0, 1.0), 8);
    let 残りの伸び = 距離.値() - 1.0;
    assert!((残りの伸び - 1.0 / 3.0).abs() < 1.0e-4, "残りの伸び{残りの伸び}");
    assert!(残りの伸び > 0.0 && 残りの伸び < 1.0);
}

#[test]
fn 硬い拘束の2回目の反復は増分0で乗数を変えない() {
    let 係数 = 係数(1.0, 0.0, 1.0 / 60.0);
    let (_, 乗数1回) = 反復して距離と乗数を測る(&係数, 点(0.0, 1.0), 点(2.0, 1.0), 1);
    let (_, 乗数2回) = 反復して距離と乗数を測る(&係数, 点(0.0, 1.0), 点(2.0, 1.0), 2);
    assert!((乗数1回.値() - 乗数2回.値()).abs() < 1.0e-6);
}
