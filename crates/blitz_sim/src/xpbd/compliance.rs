//! 拘束の柔らかさを表す物性の値。単位はメートル毎ニュートン(秒の2乗毎キログラム)であり、0で硬い拘束、正で有限の柔らかさになる。
//! 参照: `_doc/設計/XPBD共通拘束基盤.md`「判断1」「判断2」。

use blitz_math::逆キログラム;
use thiserror::Error;

use super::time_step_width::刻み幅;

/// メートル毎ニュートン単位のコンプライアンス。0以上の有限値だけを持つ。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct コンプライアンス(f32);

impl コンプライアンス {
    /// 負と非有限を型付きエラーで拒む。0は硬い拘束として許す。
    pub fn 生成する(値: f32) -> Result<Self, コンプライアンスエラー> {
        if !値.is_finite() {
            return Err(コンプライアンスエラー::非有限値 { 値 });
        }
        if 値 < 0.0 {
            return Err(コンプライアンスエラー::負の値 { 値 });
        }
        Ok(Self(値))
    }

    /// 硬い拘束。
    pub fn 硬い() -> Self {
        Self(0.0)
    }

    /// 反復の式に現れる刻み依存量 α̃ = コンプライアンス ÷ 刻み幅の2乗。次元は逆質量と同じ(毎キログラム)であり、有効逆質量へそのまま足せる。
    /// 物理刻みの開始時に1度だけ導く(判断8の工程6)。単精度の表現範囲を超える組み合わせは型付きエラーで拒む。
    pub fn 刻み依存量(&self, 刻み幅: 刻み幅) -> Result<逆キログラム, コンプライアンスエラー> {
        let 刻み = 刻み幅.秒().値();
        let 値 = self.0 / (刻み * 刻み);
        逆キログラム::生成する(値).map_err(|_| コンプライアンスエラー::刻み依存量が範囲を外れた { 値 })
    }

    /// 境界向けの生値取り出し。ドメインAPI内部では使わない。
    pub fn 値(&self) -> f32 {
        self.0
    }
}

/// コンプライアンスの生成が拒んだ入力。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum コンプライアンスエラー {
    #[error("コンプライアンスは有限値でなければならない(指定値: {値})")]
    非有限値 { 値: f32 },
    #[error("コンプライアンスは0以上でなければならない(指定値: {値})")]
    負の値 { 値: f32 },
    #[error("コンプライアンスを刻み幅の2乗で割った量が単精度の範囲を外れた(結果: {値})")]
    刻み依存量が範囲を外れた { 値: f32 },
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;
    use blitz_math::秒;

    #[test]
    fn 刻み依存量は刻み幅の2乗で割った量になる() {
        let 刻み幅 = 刻み幅::生成する(秒::生成する(0.5)).unwrap();
        assert_eq!(
            コンプライアンス::生成する(0.5).unwrap().刻み依存量(刻み幅),
            Ok(逆キログラム::生成する(2.0).unwrap())
        );
        assert!(コンプライアンス::硬い().刻み依存量(刻み幅).unwrap().零か());
        let 刻み幅が極小 = 刻み幅::生成する(秒::生成する(1.0e-30)).unwrap();
        assert!(matches!(
            コンプライアンス::生成する(1.0).unwrap().刻み依存量(刻み幅が極小),
            Err(コンプライアンスエラー::刻み依存量が範囲を外れた { .. })
        ));
    }

    #[test]
    fn 負と非有限を拒む() {
        assert_eq!(コンプライアンス::生成する(-0.1), Err(コンプライアンスエラー::負の値 { 値: -0.1 }));
        assert!(matches!(
            コンプライアンス::生成する(f32::NAN),
            Err(コンプライアンスエラー::非有限値 { .. })
        ));
    }
}
