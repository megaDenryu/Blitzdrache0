//! 吊り下げた質点の定常の伸びを測る検査用の器。固定点から静止長だけ下に質点を吊り、重力で予測位置を作り、拘束を反復して位置を確定する刻みを繰り返す。
//! 速度を持たず毎刻みを静止から始める(準静的)のは、定常の伸びだけを測るためであり、減衰の無い振動が収まるのを待つ必要を無くす。
//! 正典式と旧式(距離の誤差を逆質量の比で分配する)の両方を同じ器で回し、刻み幅と反復回数を変えたときの硬さの崩れを対照する。

use blitz_math::{メートル, メートル毎秒毎秒, ワールド, 位置, 変位, 逆キログラム};

use super::compliance::コンプライアンス;
use super::distance_constraint_parameters::距離拘束の引数;
use super::distance_constraint_participant::距離拘束の参加点;
use super::distance_projection_result::距離拘束の一回の射影の結果;
use super::lagrange_multiplier::ラグランジュ乗数;
use super::pbd_distance_distribution::距離の誤差を逆質量の比で分配する;
use super::rest_length::静止長;
use super::time_step_width::刻み幅;

pub(super) struct 吊り下げの検査 {
    pub 静止長: 静止長,
    pub 逆質量: 逆キログラム,
    pub 重力: メートル毎秒毎秒,
    pub 刻み幅: 刻み幅,
    pub 反復回数: usize,
    pub 刻み数: usize,
}

impl 吊り下げの検査 {
    fn 固定点(&self) -> 距離拘束の参加点 {
        let 原点 = 位置::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0));
        距離拘束の参加点::生成する(原点, 逆キログラム::零())
    }

    fn 吊り始めの位置(&self) -> 位置<ワールド> {
        位置::生成する(メートル::生成する(0.0), self.静止長.値() * -1.0, メートル::生成する(0.0))
    }

    fn 重力で落ちる予測(&self, 位置: 位置<ワールド>) -> 位置<ワールド> {
        let 落ちる長さ = self.重力 * self.刻み幅.秒() * self.刻み幅.秒();
        位置.変位を足す(変位::成分から生成する(
            メートル::生成する(0.0),
            落ちる長さ * -1.0,
            メートル::生成する(0.0),
        ))
    }

    /// 正典式で刻みを回した後の、静止長からの伸び。
    pub fn 正典式での定常の伸び(&self, コンプライアンス: コンプライアンス) -> メートル {
        let 係数 = match 距離拘束の引数::生成する(self.静止長, コンプライアンス).刻み幅で解く係数を導く(self.刻み幅)
        {
            Ok(係数) => 係数,
            Err(エラー) => panic!("吊り下げの検査の係数を導けない: {エラー}"),
        };
        let 固定点 = self.固定点();
        let mut 質点の位置 = self.吊り始めの位置();
        for _ in 0..self.刻み数 {
            let mut 予測 = self.重力で落ちる予測(質点の位置);
            let mut 乗数 = ラグランジュ乗数::零();
            for _ in 0..self.反復回数 {
                match 係数.一回射影する(固定点, 距離拘束の参加点::生成する(予測, self.逆質量), 乗数) {
                    距離拘束の一回の射影の結果::補正した {
                        補正b,
                        更新後のラグランジュ乗数,
                        ..
                    } => {
                        予測 = 予測.変位を足す(補正b);
                        乗数 = 更新後のラグランジュ乗数;
                    }
                    退化 => panic!("吊り下げの検査で退化の枝に入った: {退化:?}"),
                }
            }
            質点の位置 = 予測;
        }
        (質点の位置 - 固定点.位置).長さ() - self.静止長.値()
    }

    /// 旧式(過緩和係数を補正に掛けて反復する現在の布の式)で刻みを回した後の、静止長からの伸び。
    pub fn 旧式での定常の伸び(&self, 過緩和係数: f32) -> メートル {
        let 固定点 = self.固定点();
        let mut 質点の位置 = self.吊り始めの位置();
        for _ in 0..self.刻み数 {
            let mut 予測 = self.重力で落ちる予測(質点の位置);
            for _ in 0..self.反復回数 {
                let 予測の成分 = [予測.x().値(), 予測.y().値(), 予測.z().値()];
                let (_, 補正b) =
                    距離の誤差を逆質量の比で分配する([0.0, 0.0, 0.0], 予測の成分, 0.0, self.逆質量.値(), self.静止長.値().値());
                let 補正 = 変位::成分から生成する(メートル::生成する(補正b[0]), メートル::生成する(補正b[1]), メートル::生成する(補正b[2]));
                予測 = 予測.変位を足す(補正.比で伸ばす(過緩和係数));
            }
            質点の位置 = 予測;
        }
        (質点の位置 - 固定点.位置).長さ() - self.静止長.値()
    }
}
