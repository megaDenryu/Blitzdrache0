//! 距離拘束を一回射影した結果。補正できた枝と、射影できない理由の枝を同じ型で返し、呼び出し側が区別できるようにする。
//! 退化を黙って補正0で返さないのは、固定どうしの拘束や潰れた拘束が反復の中で無言に無視される状態を型で見えるようにするためである。

use blitz_math::{ワールド, 変位};

use super::lagrange_multiplier::ラグランジュ乗数;

/// 距離拘束の一回の射影の結果。射影できない枝ではラグランジュ乗数は変わらず、呼び出し側は渡した値をそのまま次の反復へ持ち越す。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 距離拘束の一回の射影の結果 {
    /// 補正を求めた。呼び出し側が`位置.変位を足す(補正)`で位置を更新し、更新後のラグランジュ乗数を次の反復へ渡す。
    補正した {
        補正a: 変位<ワールド>,
        補正b: 変位<ワールド>,
        更新後のラグランジュ乗数: ラグランジュ乗数,
    },
    /// 両方の参加点の逆質量が0であり、どちらも動かせない。
    両方が固定,
    /// 2つの参加点が一致していて、補正の向きが定まらない。
    向きが定まらない,
}
