//! 目標拘束の正典式の性質の検査(Issue #37の検証): 硬い接続の収束・柔らかい接続の定常の隔たり・動く目標への追従・乗数と補正の総量の一致・退化。
//! 柔らかい接続の解析解: 準静的(毎刻みを静止から始める)に重力gで引かれる粒子が、コンプライアンスαの目標拘束で釣り合う隔たりは C = α g ÷ w である
//! (拘束力 λ ÷ 刻み幅² = −C ÷ α が重力 g ÷ w と釣り合う)。隔たりは1刻みごとに比 α̃ ÷ (w + α̃)(36/37)で解析解へ寄るため、2000刻みで単精度の桁まで届く。
//! 材料は`target_projection_test_fixtures`が持つ。

use blitz_math::{メートル, 変位, 逆キログラム};

use super::distance_constraint_participant::距離拘束の参加点;
use super::lagrange_multiplier::ラグランジュ乗数;
use super::target_projection_result::目標拘束の一回の射影の結果;
use super::target_projection_test_fixtures::{一回射影して進める, 係数, 点, 逆質量};

#[test]
fn 硬い接続は一回の射影で粒子が目標へ一致し乗数は隔たりを逆質量で割った負の値になる() {
    let (粒子, 乗数) = 一回射影して進める(&係数(0.0, 1.0 / 60.0), 点(2.0, 0.0), 0.5, 点(0.0, 0.0), ラグランジュ乗数::零());
    assert!((粒子 - 点(0.0, 0.0)).長さ().値() < 1.0e-6, "粒子{粒子:?}");
    assert!((乗数.値() - (-4.0)).abs() < 1.0e-5, "乗数{}", 乗数.値());
}

#[test]
fn 柔らかい接続の定常の隔たりはコンプライアンスと重力と逆質量から解析的に決まる() {
    let (コンプライアンス, 重力, 逆質量, 刻み幅) = (0.01f32, 9.8f32, 1.0f32, 1.0 / 60.0f32);
    let 係数 = 係数(コンプライアンス, 刻み幅);
    let 目標 = 点(0.0, 0.0);
    let mut 粒子 = 目標;
    for _ in 0..2000 {
        let mut 予測 = 粒子.変位を足す(変位::成分から生成する(
            メートル::生成する(0.0),
            メートル::生成する(-重力 * 刻み幅 * 刻み幅),
            メートル::生成する(0.0),
        ));
        let mut 乗数 = ラグランジュ乗数::零();
        for _ in 0..8 {
            (予測, 乗数) = 一回射影して進める(&係数, 予測, 逆質量, 目標, 乗数);
        }
        粒子 = 予測;
    }
    let 隔たり = (粒子 - 目標).長さ().値();
    let 解析解 = コンプライアンス * 重力 / 逆質量;
    assert!((隔たり - 解析解).abs() < 1.0e-5, "隔たり{隔たり}に対して解析解{解析解}");
}

#[test]
fn 目標が毎刻み動くと硬い接続の粒子は動いた目標へ追従する() {
    let 係数 = 係数(0.0, 1.0 / 60.0);
    let mut 粒子 = 点(0.0, 0.0);
    for 刻み in 1..=10u8 {
        let 目標 = 点(0.01 * f32::from(刻み), 0.0);
        (粒子, _) = 一回射影して進める(&係数, 粒子, 1.0, 目標, ラグランジュ乗数::零());
        assert!((粒子 - 目標).長さ().値() < 1.0e-6, "刻み{刻み}で粒子{粒子:?}が目標{目標:?}から離れている");
    }
}

/// 反証: 乗数を累積しないと、加えた補正の総量と乗数が一致しない。
#[test]
fn 乗数に逆質量を掛けた長さは反復で加えた補正の総量と一致する() {
    let 係数 = 係数(0.05, 1.0 / 60.0);
    let (始点, 目標, 逆質量) = (点(1.0, 0.0), 点(0.0, 0.0), 2.0f32);
    let mut 粒子 = 始点;
    let mut 乗数 = ラグランジュ乗数::零();
    for _ in 0..6 {
        (粒子, 乗数) = 一回射影して進める(&係数, 粒子, 逆質量, 目標, 乗数);
    }
    let 加えた補正の長さ = (粒子 - 始点).長さ().値();
    assert!(加えた補正の長さ > 0.0);
    assert!(
        (加えた補正の長さ - (-乗数.値() * 逆質量)).abs() < 1.0e-6,
        "補正{加えた補正の長さ}に対して乗数{}",
        乗数.値()
    );
}

#[test]
fn 粒子が目標と一致していれば補正せず乗数も変えず逆質量零の粒子は固定の枝になる() {
    let 係数 = 係数(0.0, 1.0 / 60.0);
    let 乗数 = ラグランジュ乗数::長さを逆質量で割って生成する(メートル::生成する(-1.0), 逆質量(2.0));
    let 一致 = 距離拘束の参加点::生成する(点(1.0, 1.0), 逆質量(1.0));
    assert_eq!(
        係数.一回射影する(一致, 点(1.0, 1.0), 乗数),
        目標拘束の一回の射影の結果::目標と一致している
    );
    let 固定 = 距離拘束の参加点::生成する(点(0.0, 0.0), 逆キログラム::零());
    assert_eq!(係数.一回射影する(固定, 点(1.0, 1.0), 乗数), 目標拘束の一回の射影の結果::粒子が固定);
}
