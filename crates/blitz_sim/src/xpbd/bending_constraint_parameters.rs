//! 曲げ拘束の静的な引数(判断4の3区分のうち静的な引数)。静止角と曲げのコンプライアンスを持ち、刻み幅を受けて一刻みの係数を導く。
//! 線(3点の折れ角)と面(4点の二面角)は同じ引数を持ち、違うのは角と勾配の測り方だけである(判断11)。
//! 静止角とコンプライアンスはどちらも生成で定義域を検査した型であるため、この型の生成は失敗しない。

use super::bending_canonical_projection::曲げ拘束の一刻みの係数;
use super::bending_compliance::{曲げのコンプライアンス, 曲げのコンプライアンスエラー};
use super::rest_angle::静止角;
use super::time_step_width::刻み幅;

/// 曲げ拘束の静的な引数。参加点の添字は持たない(参加点は射影のたびに位置と逆質量として渡す)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 曲げ拘束の引数 {
    /// 拘束が保とうとする角。−πからπまでの有限値であることを型が保証する。
    pub 静止角: 静止角,
    /// 曲げの柔らかさ。0で硬い曲げ。伸びのコンプライアンスとは独立の物性である。
    pub コンプライアンス: 曲げのコンプライアンス,
}

impl 曲げ拘束の引数 {
    /// 検査済みの静止角とコンプライアンスを束ねる。
    pub fn 生成する(静止角: 静止角, コンプライアンス: 曲げのコンプライアンス) -> Self {
        Self {
            静止角, コンプライアンス
        }
    }

    /// この刻み幅で反復に使う係数。物理刻みの開始時に1度だけ呼び、その刻みの全反復で同じ係数を使う(判断8の工程6)。
    pub fn 刻み幅で解く係数を導く(
        &self,
        刻み幅: 刻み幅,
    ) -> Result<曲げ拘束の一刻みの係数, 曲げのコンプライアンスエラー> {
        Ok(曲げ拘束の一刻みの係数::生成する(
            self.静止角,
            self.コンプライアンス.刻み依存量(刻み幅)?,
        ))
    }
}
