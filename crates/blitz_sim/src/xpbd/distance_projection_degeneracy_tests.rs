//! 退化の検査(Issue #34の検証): 両方が固定と2点の一致で非数を作らず、理由の枝を返すこと。
//! 結果の型の退化の枝は数値を持たないため、その枝が返ること自体が非数を作っていないことの証明である。

use super::distance_projection_result::距離拘束の一回の射影の結果;
use super::distance_projection_test_fixtures::{係数, 点};
use super::lagrange_multiplier::ラグランジュ乗数;

#[test]
fn 両方が固定なら硬くても柔らかくても理由の枝を返す() {
    for コンプライアンス in [0.0, 0.01] {
        let 結果 = 係数(1.0, コンプライアンス, 1.0 / 60.0).一回射影する(点(0.0, 0.0), 点(2.0, 0.0), ラグランジュ乗数::零());
        assert_eq!(結果, 距離拘束の一回の射影の結果::両方が固定);
    }
}

#[test]
fn 二点が一致すれば向きが定まらない枝を返す() {
    let 係数 = 係数(1.0, 0.0, 1.0 / 60.0);
    let 零 = ラグランジュ乗数::零();
    assert_eq!(
        係数.一回射影する(点(0.0, 1.0), 点(0.0, 1.0), 零),
        距離拘束の一回の射影の結果::向きが定まらない
    );
    assert_eq!(
        係数.一回射影する(点(0.0, 1.0), 点(1.0e-8, 1.0), 零),
        距離拘束の一回の射影の結果::向きが定まらない
    );
}

#[test]
fn 一致した二点の後に乗数を持ち越しても値は変わらない() {
    let 係数 = 係数(1.0, 0.0, 1.0 / 60.0);
    let 持ち越す乗数 = ラグランジュ乗数::零();
    let 結果 = 係数.一回射影する(点(0.0, 1.0), 点(0.0, 1.0), 持ち越す乗数);
    assert_eq!(結果, 距離拘束の一回の射影の結果::向きが定まらない);
    assert_eq!(持ち越す乗数, ラグランジュ乗数::零());
}
