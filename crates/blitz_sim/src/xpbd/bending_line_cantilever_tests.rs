//! 片持ちの3点の線の検査(Issue #38の検証): 柔らかい曲げの定常の折れ角が解析的に決まること・硬い距離拘束と混ぜても伸びが変わらず曲げだけが変わること。
//! 柔らかい曲げの解析解: 2点を固定した水平な線分の先に長さhの線分を継ぎ、先端の質点(質量m)を重力gで垂らすと、曲げの拘束力 C ÷ α が
//! 先端の重力の回転力 m g h cosφ と釣り合い、折れ角は φ = α m g h cosφ を満たす。材料は`bending_test_fixtures`が持つ。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 位置, 変位};

use super::bending_lagrange_multiplier::曲げのラグランジュ乗数;
use super::bending_line_projection::線の折れ角の幾何;
use super::bending_projection_result::線の曲げ拘束の一回の射影の結果;
use super::bending_test_fixtures::{ワールドの位置を生成する, 参加点, 曲げの係数};
use super::distance_projection_result::距離拘束の一回の射影の結果;
use super::distance_projection_test_fixtures::係数 as 距離の係数;
use super::lagrange_multiplier::ラグランジュ乗数;

/// 折れ角。一直線上の3点(曲げの面が定まらない)は折れ角0である。
fn 折れ角を測る(p0: 位置<ワールド>, p1: 位置<ワールド>, p2: 位置<ワールド>) -> f32 {
    match 線の折れ角の幾何::位置から測る(p0, p1, p2) {
        Ok(幾何) => 幾何.折れ角().値(),
        Err(線の曲げ拘束の一回の射影の結果::曲げの面が定まらない) => 0.0,
        Err(退化) => panic!("退化の枝に入った: {退化:?}"),
    }
}

/// 2点を固定した水平な線分の先に長さhの線分を継ぎ、先端を硬い距離拘束と曲げ拘束で準静的に垂らした後の先端の位置と折れ角。
/// 毎刻みを静止から始めるため、1刻みの中で反復を収束させる(刻み幅0.03秒・コンプライアンス0.05では反復1回で違反が0.93倍に縮み、200回で1e-6)。
/// 刻み幅を小さく取るのは、1刻みの落下が大きいと反復の途中で勾配の向きが回り、乗数と加えた補正の総量の対応が崩れて釣り合いが解析解からずれるためである
/// (刻み幅0.1秒では1刻みに0.098メートル落ちて折れ角が4%ずれた)。
fn 片持ちの線を垂らす(コンプライアンス: f32, 刻み数: usize) -> (位置<ワールド>, f32) {
    let (h, 逆質量, 重力, 刻み幅の秒) = (0.5f32, 1.0f32, 9.8f32, 0.03f32);
    let 曲げ = 曲げの係数(0.0, コンプライアンス, 刻み幅の秒);
    let 距離 = 距離の係数(h, 0.0, 刻み幅の秒);
    let 点0 = 参加点(ワールドの位置を生成する(-h, 0.0, 0.0), 0.0);
    let 点1 = 参加点(ワールドの位置を生成する(0.0, 0.0, 0.0), 0.0);
    let mut 先端 = ワールドの位置を生成する(h, -1.0e-3, 0.0);
    for _ in 0..刻み数 {
        let mut 予測 = 先端.変位を足す(変位::成分から生成する(
            メートル::生成する(0.0),
            メートル::生成する(-重力 * 刻み幅の秒 * 刻み幅の秒),
            メートル::生成する(0.0),
        ));
        let (mut 距離の乗数, mut 曲げの乗数) = (ラグランジュ乗数::零(), 曲げのラグランジュ乗数::零());
        for _ in 0..200 {
            if let 距離拘束の一回の射影の結果::補正した {
                補正b,
                更新後のラグランジュ乗数,
                ..
            } = 距離.一回射影する(点1, 参加点(予測, 逆質量), 距離の乗数)
            {
                予測 = 予測.変位を足す(補正b);
                距離の乗数 = 更新後のラグランジュ乗数;
            }
            if let 線の曲げ拘束の一回の射影の結果::補正した {
                補正2,
                更新後のラグランジュ乗数,
                ..
            } = 曲げ.線を一回射影する(点0, 点1, 参加点(予測, 逆質量), 曲げの乗数)
            {
                予測 = 予測.変位を足す(補正2);
                曲げの乗数 = 更新後のラグランジュ乗数;
            }
        }
        先端 = 予測;
    }
    (先端, 折れ角を測る(点0.位置, 点1.位置, 先端))
}

#[test]
fn 柔らかい曲げで垂らした先端の折れ角は回転力の釣り合いの解析解を満たす() {
    let コンプライアンス = 0.05f32;
    let (_, 折れ角) = 片持ちの線を垂らす(コンプライアンス, 400);
    let 釣り合いの残差 = 折れ角 - コンプライアンス * 9.8 * 0.5 * 折れ角.cos();
    assert!(折れ角 > 0.1 && 折れ角 < 0.4, "折れ角{折れ角}");
    assert!(釣り合いの残差.abs() < 1.0e-3, "折れ角{折れ角}の釣り合いの残差{釣り合いの残差}");
}

/// 反証: 距離のコンプライアンスを倍率で流用して曲げを表すと、曲げを柔らかくしたときに線分の長さも変わる。
#[test]
fn 硬い距離拘束と混ぜても曲げのコンプライアンスは伸びを変えず折れ角だけを変える() {
    let mut 前の折れ角 = -1.0f32;
    for コンプライアンス in [0.0f32, 0.05, 0.5] {
        let (先端, 折れ角) = 片持ちの線を垂らす(コンプライアンス, 400);
        let 長さ = (先端 - ワールドの位置を生成する(0.0, 0.0, 0.0)).長さ().値();
        assert!((長さ - 0.5).abs() < 1.0e-4, "コンプライアンス{コンプライアンス}で線分の長さ{長さ}");
        assert!(
            折れ角 > 前の折れ角,
            "コンプライアンス{コンプライアンス}で折れ角{折れ角}が前{前の折れ角}より小さい"
        );
        前の折れ角 = 折れ角;
    }
    assert!(前の折れ角 > 1.0);
}
