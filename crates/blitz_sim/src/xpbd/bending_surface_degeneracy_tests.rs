//! 面の曲げ拘束の退化の検査(Issue #38の検証): 全て固定・辺が潰れている・三角形が潰れているで非数を作らず、理由の枝を返して乗数を変えないこと。
//! 結果の型の退化の枝は数値を持たないため、その枝が返ること自体が非数を作っていないことの証明である。4点と参加点の組み立ては`bending_surface_projection_tests`が持つ。

use super::bending_lagrange_multiplier::曲げのラグランジュ乗数;
use super::bending_projection_result::面の曲げ拘束の一回の射影の結果;
use super::bending_surface_projection_tests::{参加点一覧, 四点};
use super::bending_test_fixtures::{ワールドの位置を生成する, 曲げの係数};

#[test]
fn 退化は理由の枝を返し乗数を変えない() {
    let 係数 = 曲げの係数(0.0, 0.0, 1.0 / 60.0);
    let 乗数 = 曲げのラグランジュ乗数::零();
    let 固定 = 参加点一覧(四点(0.5, 0.5), 0.0);
    assert_eq!(
        係数.面を一回射影する(固定[0], 固定[1], 固定[2], 固定[3], 乗数),
        面の曲げ拘束の一回の射影の結果::全て固定
    );
    let mut 辺が潰れた = 参加点一覧(四点(0.5, 0.5), 1.0);
    辺が潰れた[1].位置 = 辺が潰れた[0].位置;
    assert_eq!(
        係数.面を一回射影する(辺が潰れた[0], 辺が潰れた[1], 辺が潰れた[2], 辺が潰れた[3], 乗数),
        面の曲げ拘束の一回の射影の結果::辺が潰れている
    );
    let mut 三角形が潰れた = 参加点一覧(四点(0.5, 0.5), 1.0);
    三角形が潰れた[2].位置 = ワールドの位置を生成する(0.5, 0.0, 0.0);
    assert_eq!(
        係数.面を一回射影する(三角形が潰れた[0], 三角形が潰れた[1], 三角形が潰れた[2], 三角形が潰れた[3], 乗数),
        面の曲げ拘束の一回の射影の結果::三角形が潰れている
    );
    assert_eq!(乗数, 曲げのラグランジュ乗数::零());
}
