//! 線の曲げ拘束の正典式の性質の検査(Issue #38の検証): 勾配が数値微分と一致すること・硬い曲げが折れた状態から静止角へ収束すること・
//! 退化の枝が非数を作らず乗数を変えないこと。片持ちの線の釣り合い(柔らかい曲げの解析解・伸びと曲げの独立)は`bending_line_cantilever_tests`が持つ。
//! 材料は`bending_test_fixtures`が持つ。

#![allow(clippy::unwrap_used)]

use super::bending_lagrange_multiplier::曲げのラグランジュ乗数;
use super::bending_line_projection::線の折れ角の幾何;
use super::bending_projection_result::線の曲げ拘束の一回の射影の結果;
use super::bending_test_fixtures::{
    ワールドの位置を生成する, 勾配が数値微分と一致することを確かめる, 参加点, 曲げの係数
};

#[test]
fn 折れ角は真っ直ぐで零で直角で四分の一周であり勾配は数値微分と一致する() {
    let 点一覧 = [
        ワールドの位置を生成する(0.0, 0.0, 0.0),
        ワールドの位置を生成する(1.0, 0.2, 0.0),
        ワールドの位置を生成する(1.5, 1.0, 0.3),
    ];
    let 幾何 = 線の折れ角の幾何::位置から測る(点一覧[0], 点一覧[1], 点一覧[2]).unwrap();
    勾配が数値微分と一致することを確かめる(&点一覧, &幾何.勾配(), |点| {
        線の折れ角の幾何::位置から測る(点[0], 点[1], 点[2]).unwrap().折れ角().値()
    });
    let 直角 = 線の折れ角の幾何::位置から測る(
        ワールドの位置を生成する(0.0, 0.0, 0.0),
        ワールドの位置を生成する(1.0, 0.0, 0.0),
        ワールドの位置を生成する(1.0, 1.0, 0.0),
    )
    .unwrap();
    assert!((直角.折れ角().値() - std::f32::consts::FRAC_PI_2).abs() < 1.0e-6);
}

/// 反証: 勾配の符号を反転すると、折れた線は静止角から離れる向きへ動く。
#[test]
fn 硬い曲げは折れた3点を静止角へ収束させ2回目以降の増分は零に近づく() {
    for 静止角 in [0.0f32, 0.5] {
        let 係数 = 曲げの係数(静止角, 0.0, 1.0 / 60.0);
        let mut 点 = [
            参加点(ワールドの位置を生成する(0.0, 0.0, 0.0), 1.0),
            参加点(ワールドの位置を生成する(1.0, 0.0, 0.0), 1.0),
            参加点(ワールドの位置を生成する(1.0, 1.0, 0.0), 1.0),
        ];
        let mut 乗数 = 曲げのラグランジュ乗数::零();
        for _ in 0..40 {
            match 係数.線を一回射影する(点[0], 点[1], 点[2], 乗数) {
                線の曲げ拘束の一回の射影の結果::補正した {
                    補正0,
                    補正1,
                    補正2,
                    更新後のラグランジュ乗数,
                } => {
                    点[0].位置 = 点[0].位置.変位を足す(補正0);
                    点[1].位置 = 点[1].位置.変位を足す(補正1);
                    点[2].位置 = 点[2].位置.変位を足す(補正2);
                    乗数 = 更新後のラグランジュ乗数;
                }
                線の曲げ拘束の一回の射影の結果::曲げの面が定まらない => break, // 真っ直ぐになった(静止角0の拘束は満たされている)
                退化 => panic!("退化の枝に入った: {退化:?}"),
            }
        }
        let 折れ角 = match 線の折れ角の幾何::位置から測る(点[0].位置, 点[1].位置, 点[2].位置) {
            Ok(幾何) => 幾何.折れ角().値(),
            Err(_) => 0.0, // 真っ直ぐになった
        };
        assert!((折れ角 - 静止角).abs() < 1.0e-3, "静止角{静止角}に対して折れ角{折れ角}");
        assert!(乗数.値() < 0.0);
    }
}

#[test]
fn 退化は理由の枝を返し乗数を変えない() {
    let 係数 = 曲げの係数(0.3, 0.0, 1.0 / 60.0);
    let 乗数 = 曲げのラグランジュ乗数::零();
    let (原点, x1, x2) = (
        ワールドの位置を生成する(0.0, 0.0, 0.0),
        ワールドの位置を生成する(1.0, 0.0, 0.0),
        ワールドの位置を生成する(2.0, 0.0, 0.0),
    );
    assert_eq!(
        係数.線を一回射影する(参加点(原点, 0.0), 参加点(x1, 0.0), 参加点(x2, 0.0), 乗数),
        線の曲げ拘束の一回の射影の結果::全て固定
    );
    assert_eq!(
        係数.線を一回射影する(参加点(原点, 1.0), 参加点(x1, 1.0), 参加点(x2, 1.0), 乗数),
        線の曲げ拘束の一回の射影の結果::曲げの面が定まらない
    );
    assert_eq!(
        係数.線を一回射影する(参加点(原点, 1.0), 参加点(原点, 1.0), 参加点(x2, 1.0), 乗数),
        線の曲げ拘束の一回の射影の結果::線分が潰れている
    );
    assert_eq!(乗数, 曲げのラグランジュ乗数::零());
}
