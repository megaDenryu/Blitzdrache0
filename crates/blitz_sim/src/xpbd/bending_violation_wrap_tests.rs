//! 曲げ拘束の拘束違反の弧の畳みの検査(Issue #38のcodexレビューの是正): 静止角が±πのとき・違反がちょうど±πのときにCPUの正本が違反を正のπへ決め、
//! 補正の向きが静止角の符号に依らず固定されること。GPUの写し(`shaders/xpbd_bending_projection.slang`の`wrapToShortestArc`)は同じ演算の順
//! (余りを取り、負なら一周を足し、半周を越えれば一周を引く)で書かれており、同じ入力の手計算は次のとおり一致する。
//!   −π: 余り(−π, 2π) = −π → 負なので一周を足してπ → π > πは偽 → π。  +π: 余り(π, 2π) = π → 非負 → π > πは偽 → π。
//! 現在の角と静止角がどちらも−πからπまでにある限り違反は−2πから2πまでにあり、余りの整数商は0か−1だけであるため、両側の丸めの経路も同じである。

use std::f32::consts::PI;

use blitz_math::ラジアン;

use super::bending_lagrange_multiplier::曲げのラグランジュ乗数;
use super::bending_projection_result::面の曲げ拘束の一回の射影の結果;
use super::bending_surface_projection_tests::{参加点一覧, 四点};
use super::bending_test_fixtures::曲げの係数;

#[test]
fn 静止角が正負の半周でも現在の角が零なら違反は正の半周に決まる() {
    for 静止角 in [PI, -PI] {
        let 係数 = 曲げの係数(静止角, 0.0, 1.0 / 60.0);
        assert_eq!(係数.拘束違反(ラジアン::生成する(0.0)), ラジアン::生成する(PI), "静止角{静止角}");
    }
}

#[test]
fn 違反がちょうど正負の半周なら正の半周に決まる() {
    let 係数 = 曲げの係数(0.0, 0.0, 1.0 / 60.0);
    assert_eq!(係数.拘束違反(ラジアン::生成する(PI)), ラジアン::生成する(PI));
    assert_eq!(係数.拘束違反(ラジアン::生成する(-PI)), ラジアン::生成する(PI));
}

/// 反証: 畳みを条件分岐で挟むと、静止角+πでは違反が−πのまま残り、補正の向きが静止角−πのときと逆になる。
#[test]
fn 平らな面は静止角が正負どちらの半周でも同じ向きへ折られる() {
    let 点 = 参加点一覧(四点(0.0, 0.0), 1.0);
    let 射影する =
        |静止角: f32| 曲げの係数(静止角, 0.0, 1.0 / 60.0).面を一回射影する(点[0], 点[1], 点[2], 点[3], 曲げのラグランジュ乗数::零());
    let (正の半周, 負の半周) = (射影する(PI), 射影する(-PI));
    assert_eq!(正の半周, 負の半周);
    let 面の曲げ拘束の一回の射影の結果::補正した {
        補正c,
        更新後のラグランジュ乗数,
        ..
    } = 正の半周
    else {
        panic!("退化の枝に入った: {正の半周:?}");
    };
    assert!(
        更新後のラグランジュ乗数 < 曲げのラグランジュ乗数::零(),
        "乗数{更新後のラグランジュ乗数:?}"
    );
    assert!(補正c.z().値() < 0.0, "翼cの補正{補正c:?}");
}
