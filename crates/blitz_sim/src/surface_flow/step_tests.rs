//! 表面流CPU参照計算の質量保存、下流移動、非負性を固定する。

#![allow(clippy::unwrap_used)]

use super::{表面流仕様, 表面流状態};

fn 仕様() -> 表面流仕様 {
    表面流仕様::生成する([5, 5], 1.0, 0.25, [0.0, 4.0], 1.0).unwrap()
}

#[test]
fn 流出なし境界で総液量を保存する() {
    let 初期 = 表面流状態::空で生成する(&仕様()).液膜を設定する([2, 2], 1.0).unwrap();
    let 次 = 初期.一ステップ進める(&仕様()).unwrap();
    assert!((次.総液膜厚さ() - 初期.総液膜厚さ()).abs() < 1e-6);
}

#[test]
fn 重力接線方向の隣接セルへ液膜が移る() {
    let 初期 = 表面流状態::空で生成する(&仕様()).液膜を設定する([2, 2], 1.0).unwrap();
    let 次 = 初期.一ステップ進める(&仕様()).unwrap();
    assert!(次.セル([2, 3]).unwrap().液膜厚さ() > 0.0);
    assert!(次.セル([2, 2]).unwrap().液膜厚さ() < 1.0);
}

#[test]
fn 大きな時間刻みでも液膜厚さは負にならない() {
    let 仕様 = 表面流仕様::生成する([3, 3], 0.1, 1.0, [100.0, 100.0], 1.0).unwrap();
    let 初期 = 表面流状態::空で生成する(&仕様).液膜を設定する([1, 1], 1.0).unwrap();
    let 次 = 初期.一ステップ進める(&仕様).unwrap();
    for 行 in 0..3 {
        for 列 in 0..3 {
            assert!(次.セル([列, 行]).unwrap().液膜厚さ() >= 0.0);
        }
    }
}
