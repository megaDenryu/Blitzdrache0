//! 表面流状態の時間発展の工程。現在の状態と表面流仕様を受け取り、速度を更新してから
//! 保存的な液膜移流を行った次の状態を返す。状態の生成と参照は state.rs が持つ。

use super::cell::表面セル;
use super::error::表面流仕様エラー;
use super::flux::流出割合を計算する;
use super::spec::表面流仕様;
use super::state::{usizeへ, 表面流状態};

impl 表面流状態 {
    pub fn 一ステップ進める(&self, 仕様: &表面流仕様) -> Result<Self, 表面流仕様エラー> {
        let [列数u32, 行数u32] = 仕様.格子寸法();
        if self.格子寸法() != 仕様.格子寸法() {
            return Err(表面流仕様エラー::格子寸法が不一致 {
                状態: self.格子寸法(),
                仕様: 仕様.格子寸法(),
            });
        }
        let (列数, 行数) = (usizeへ(列数u32), usizeへ(行数u32));
        let mut 厚さ一覧: Vec<f32> = self.セル一覧().iter().map(表面セル::液膜厚さ).collect();
        let mut 速度一覧 = Vec::with_capacity(self.セル一覧().len());
        for セル in self.セル一覧() {
            速度一覧.push(速度を進める(セル.接線速度(), 仕様));
        }
        for 行 in 0..行数 {
            for 列 in 0..列数 {
                let 添字 = 行 * 列数 + 列;
                let 厚さ = self.セル一覧()[添字].液膜厚さ();
                let 割合 = 流出割合を計算する(速度一覧[添字], 仕様.時間刻み(), 仕様.セル幅());
                流す(&mut 厚さ一覧, 列数, [列, 行], [列, 行.wrapping_sub(1)], 行 > 0, 厚さ * 割合[0]);
                流す(&mut 厚さ一覧, 列数, [列, 行], [列, 行 + 1], 行 + 1 < 行数, 厚さ * 割合[1]);
                流す(&mut 厚さ一覧, 列数, [列, 行], [列.wrapping_sub(1), 行], 列 > 0, 厚さ * 割合[2]);
                流す(&mut 厚さ一覧, 列数, [列, 行], [列 + 1, 行], 列 + 1 < 列数, 厚さ * 割合[3]);
            }
        }
        let セル一覧 = 厚さ一覧
            .into_iter()
            .zip(速度一覧)
            .map(|(厚さ, 速度)| 表面セル::生成する(厚さ.max(0.0), 速度))
            .collect();
        Ok(Self::構築する([列数u32, 行数u32], セル一覧))
    }
}

fn 速度を進める(速度: [f32; 2], 仕様: &表面流仕様) -> [f32; 2] {
    let 加速度 = 仕様.重力接線成分();
    let 時間 = 仕様.時間刻み();
    let 減衰 = 仕様.速度減衰();
    [(速度[0] + 加速度[0] * 時間) * 減衰, (速度[1] + 加速度[1] * 時間) * 減衰]
}

fn 流す(厚さ: &mut [f32], 列数: usize, 元: [usize; 2], 先: [usize; 2], 有効: bool, 量: f32) {
    if !有効 || 量 <= 0.0 {
        return;
    }
    let 元添字 = 元[1] * 列数 + 元[0];
    let 先添字 = 先[1] * 列数 + 先[0];
    厚さ[元添字] -= 量;
    厚さ[先添字] += 量;
}
