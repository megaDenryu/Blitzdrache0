//! 表面流仕様と状態更新の型付きエラー。

use thiserror::Error;

#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 表面流仕様エラー {
    #[error("格子の列数と行数は2以上でなければならない(列: {列数}, 行: {行数})")]
    格子が小さすぎる { 列数: u32, 行数: u32 },
    #[error("セル幅は正の有限値でなければならない(指定値: {指定値})")]
    セル幅が不正 { 指定値: f32 },
    #[error("時間刻みは正の有限値でなければならない(指定値: {指定値})")]
    時間刻みが不正 { 指定値: f32 },
    #[error("速度減衰は0以上1以下でなければならない(指定値: {指定値})")]
    速度減衰が不正 { 指定値: f32 },
    #[error("セル座標が格子の範囲外(列: {列}, 行: {行})")]
    セル座標が範囲外 { 列: u32, 行: u32 },
    #[error("液膜厚さは0以上の有限値でなければならない(指定値: {指定値})")]
    液膜厚さが不正 { 指定値: f32 },
    #[error("状態と仕様の格子寸法が一致しない(状態: {状態:?}, 仕様: {仕様:?})")]
    格子寸法が不一致 { 状態: [u32; 2], 仕様: [u32; 2] },
}
