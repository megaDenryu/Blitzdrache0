//! 1セルから上下左右へ出る保存的な風上流束。

pub(crate) fn 流出割合を計算する(速度: [f32; 2], 時間刻み: f32, セル幅: f32) -> [f32; 4] {
    let 比 = 時間刻み / セル幅;
    let mut 割合 = [
        (-速度[1]).max(0.0) * 比,
        速度[1].max(0.0) * 比,
        (-速度[0]).max(0.0) * 比,
        速度[0].max(0.0) * 比,
    ];
    let 合計: f32 = 割合.iter().sum();
    if 合計 > 1.0 {
        for 値 in &mut 割合 {
            *値 /= 合計;
        }
    }
    割合
}
