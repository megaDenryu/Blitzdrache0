//! SPHの圧力・粘性・重力を半陰的オイラーで1ステップ進める。

use super::density::{sph密度を計算する, 距離二乗};
use super::kernel::{圧力勾配係数, 粘性ラプラシアン};
use super::particle::流体粒子;
use super::spec::Sph仕様;

pub fn sphを一ステップ進める(粒子一覧: &[流体粒子], 仕様: &Sph仕様) -> Vec<流体粒子> {
    let 密度一覧 = sph密度を計算する(粒子一覧, 仕様);
    let 圧力一覧: Vec<f32> = 密度一覧.iter().map(|密度| 仕様.圧力剛性() * (*密度 - 仕様.静止密度()).max(0.0)).collect();
    粒子一覧
        .iter()
        .enumerate()
        .map(|(添字, 粒子)| {
            let 加速度 = 加速度を計算する(添字, 粒子一覧, &密度一覧, &圧力一覧, 仕様);
            let 時間 = 仕様.時間刻み();
            let 速度 = 加算する(粒子.速度(), 倍率を掛ける(加速度, 時間));
            let 位置 = 加算する(粒子.位置(), 倍率を掛ける(速度, 時間));
            let (位置, 速度) = 境界を適用する(位置, 速度, 仕様);
            粒子.更新する(位置, 速度)
        })
        .collect()
}

fn 加速度を計算する(対象添字: usize, 粒子一覧: &[流体粒子], 密度: &[f32], 圧力: &[f32], 仕様: &Sph仕様) -> [f32; 3] {
    let 対象 = 粒子一覧[対象添字];
    let mut 加速度 = 仕様.重力加速度();
    for (近傍添字, 近傍) in 粒子一覧.iter().enumerate() {
        if 対象添字 == 近傍添字 {
            continue;
        }
        let 差 = 差を得る(対象.位置(), 近傍.位置());
        let 距離 = 距離二乗(対象.位置(), 近傍.位置()).sqrt();
        if 距離 <= f32::EPSILON || 距離 >= 仕様.平滑化半径() {
            continue;
        }
        let 圧力係数 = -近傍.質量() * (圧力[対象添字] + 圧力[近傍添字]) / (2.0 * 密度[対象添字] * 密度[近傍添字]);
        加速度 = 加算する(加速度, 倍率を掛ける(差, 圧力係数 * 圧力勾配係数(距離, 仕様.平滑化半径()) / 距離));
        let 速度差 = 差を得る(近傍.速度(), 対象.速度());
        let 粘性係数 = 仕様.粘性係数() * 近傍.質量() * 粘性ラプラシアン(距離, 仕様.平滑化半径()) / (密度[対象添字] * 密度[近傍添字]);
        加速度 = 加算する(加速度, 倍率を掛ける(速度差, 粘性係数));
    }
    加速度
}

fn 境界を適用する(mut 位置: [f32; 3], mut 速度: [f32; 3], 仕様: &Sph仕様) -> ([f32; 3], [f32; 3]) {
    let [最小, 最大] = 仕様.境界();
    for 軸 in 0..3 {
        if 位置[軸] < 最小[軸] {
            位置[軸] = 最小[軸];
            速度[軸] = 速度[軸].abs() * 仕様.反発係数();
        }
        if 位置[軸] > 最大[軸] {
            位置[軸] = 最大[軸];
            速度[軸] = -速度[軸].abs() * 仕様.反発係数();
        }
    }
    (位置, 速度)
}

fn 差を得る(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    [a[0] - b[0], a[1] - b[1], a[2] - b[2]]
}
fn 加算する(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    [a[0] + b[0], a[1] + b[1], a[2] + b[2]]
}
fn 倍率を掛ける(a: [f32; 3], 倍率: f32) -> [f32; 3] {
    [a[0] * 倍率, a[1] * 倍率, a[2] * 倍率]
}
