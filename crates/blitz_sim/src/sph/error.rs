//! SPH仕様の型付きエラー。

use thiserror::Error;

#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum Sph仕様エラー {
    #[error("{項目}は正の有限値でなければならない(指定値: {指定値})")]
    正値が必要 { 項目: &'static str, 指定値: f32 },
    #[error("粘性係数は0以上の有限値でなければならない(指定値: {指定値})")]
    粘性係数が不正 { 指定値: f32 },
    #[error("反発係数は0以上1以下でなければならない(指定値: {指定値})")]
    反発係数が不正 { 指定値: f32 },
    #[error("境界の最小値は最大値より小さくなければならない(軸: {軸})")]
    境界が不正 { 軸: usize },
    #[error("粒子の質量は正の有限値でなければならない(指定値: {指定値})")]
    粒子質量が不正 { 指定値: f32 },
    #[error("粒子の{項目}に有限でない成分がある")]
    粒子ベクトルが不正 { 項目: &'static str },
}
