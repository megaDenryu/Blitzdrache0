//! 掃引の変位のうち、形に触れるまでに動けた分の割合。0以上1以下の無次元量である。
//!
//! 単精度で持つのは、この割合を掛ける相手(理想距離・望みの変位)がどれも単精度のメートルであるためである。
//! 世界側の問い合わせは倍精度の割合を答えるため、倍精度から作る入口を別に持ち、狭める境界をそこへ閉じる。

use std::fmt;

use blitz_math::{倍精度の無次元量を単精度へ狭める, 単位変換エラー};

#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 動けた割合(f32);

/// 動けた割合として受理できない値の理由。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 動けた割合エラー {
    範囲外,                               // 0以上1以下の有限値でない
    単精度へ狭められない(単位変換エラー), // 倍精度の値を単精度へ狭めた結果が有限でない
}

impl fmt::Display for 動けた割合エラー {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::範囲外 => write!(formatter, "動けた割合が0以上1以下の有限値でない"),
            Self::単精度へ狭められない(誤り) => write!(formatter, "動けた割合を単精度へ狭められない: {誤り}"),
        }
    }
}

impl std::error::Error for 動けた割合エラー {}

impl 動けた割合 {
    /// 0以上1以下の有限値だけを受け付ける。
    pub fn 生成する(値: f32) -> Result<Self, 動けた割合エラー> {
        if !値.is_finite() || !(0.0..=1.0).contains(&値) {
            return Err(動けた割合エラー::範囲外);
        }
        Ok(Self(値))
    }

    /// 世界側が答えた倍精度の割合から作る。狭める境界はここ1箇所である。
    pub fn 倍精度から生成する(値: f64) -> Result<Self, 動けた割合エラー> {
        let 狭めた = 倍精度の無次元量を単精度へ狭める(値).map_err(動けた割合エラー::単精度へ狭められない)?;
        Self::生成する(狭めた)
    }

    /// 動く前から触れていた場合の割合。
    pub fn 一歩も動けなかった() -> Self {
        Self(0.0)
    }

    /// 割合を減らし、0を下回るなら0で止めた割合。減らす量が有限でなければ0で止める。
    pub fn 減らして零で止める(self, 減らす割合: f32) -> Self {
        Self((self.0 - 減らす割合).max(0.0))
    }

    pub fn 値(self) -> f32 {
        self.0
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 範囲の内側の値を受理する() {
        assert_eq!(動けた割合::生成する(0.25).map(動けた割合::値), Ok(0.25));
        assert_eq!(動けた割合::倍精度から生成する(1.0).map(動けた割合::値), Ok(1.0));
    }

    #[test]
    fn 減らした割合は零で止まる() {
        let 割合 = 動けた割合::生成する(0.3).map(|割合| 割合.減らして零で止める(0.1)).map(動けた割合::値);
        assert_eq!(割合, Ok(0.3 - 0.1));
        assert_eq!(動けた割合::一歩も動けなかった().減らして零で止める(0.1).値(), 0.0);
        assert_eq!(動けた割合::一歩も動けなかった().減らして零で止める(f32::NAN).値(), 0.0);
    }

    #[test]
    fn 範囲の外と非有限を拒む() {
        assert_eq!(動けた割合::生成する(1.5), Err(動けた割合エラー::範囲外));
        assert_eq!(動けた割合::生成する(-0.1), Err(動けた割合エラー::範囲外));
        assert_eq!(
            動けた割合::倍精度から生成する(f64::NAN),
            Err(動けた割合エラー::単精度へ狭められない(単位変換エラー::非有限値))
        );
    }
}
