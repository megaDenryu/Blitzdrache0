//! 「前へ進む」操作がどの向きを指すかを表す角。触れるのは角そのものだけであり、その角がどこから来たか(カメラなのか、
//! 固定の方位なのか)を知らない。
//!
//! 角の測り方はY軸まわりの正の回転である。0が北(Zの負の向き)、増えると西(Xの負の向き)へ回る。
//! ワールド軸はXが東、Yが天頂、Zが南であり(`_doc/計画/ユビキタス言語.md`「太陽方向」)、X×Yが南を向く右手系であるため、
//! Y軸まわりの正の回転は南を東へ、北を西へ回す。
//!
//! 型で包むのは、同じラジアンでも「前がどちらか」と「太陽がどちらか」では混ぜてはならない量だからである。

use blitz_math::ラジアン;

use crate::facing_azimuth::動く個体が向いている方位角;
use crate::horizontal_unit_vector::水平面の単位ベクトル;

/// 「前へ進む」操作が指す向きの方位角。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 前へ進む向きの方位角(ラジアン);

impl 前へ進む向きの方位角 {
    pub fn 生成する(角: ラジアン) -> Self {
        Self(角)
    }

    /// 前が北を指す方位角。カメラを持たない検査と、方位を固定したい場面が使う。
    pub fn 北を指す() -> Self {
        Self(ラジアン::生成する(0.0))
    }

    /// 前へ進む向きの東成分と南成分。
    pub fn 前へ進む向きの東と南の成分(self) -> 水平面の単位ベクトル {
        水平面の単位ベクトル::方位角から生成する(self.0)
    }

    /// 右へ寄る向きの東成分と南成分。前へ進む向きをY軸まわりに90度戻した向きである。
    pub fn 右へ寄る向きの東と南の成分(self) -> 水平面の単位ベクトル {
        self.前へ進む向きの東と南の成分().方位角を直角ぶん減らした向きを返す()
    }

    /// 倒し量が指す向き。前へ倒せばこの向きそのもの、右へ倒せば90度右の向きになる。
    ///
    /// 右が方位角の減る側にあるのは、Y軸まわりの正の回転が北を西へ回すためである。
    /// 注意: 両方の倒し量が0のフレームは向きが決まらない。呼び出し側が先に中立を除く。
    pub(crate) fn 倒し量が指す向きを求める(
        self, 右への倒し量: f32, 前への倒し量: f32
    ) -> 動く個体が向いている方位角 {
        動く個体が向いている方位角::生成する(self.0 + ラジアン::生成する((-右への倒し量).atan2(前への倒し量)))
    }
}
