//! カメラの遮蔽の検査。平面と段と壁の世界で、遮蔽があれば表示距離が縮むこと・縮む向きが即時であること・
//! 評価できない描画は基準を保つこと・下限を割らないことを固定する。復帰とズームの検査は `camera_recovery_tests` にある。
//! 構図は `camera_occlusion_test_fixture` を見る。

use blitz_math::{メートル, 大域メートル};

use crate::camera_occlusion_test_fixture::{入力, 南4メートルに壁のある世界, 壁の無い世界, 描いた, 決める};
use crate::occlusion_verdict::遮蔽の判定;
use crate::previous_display_distance::前の描画の表示距離;

/// 反証: 遮蔽で表示距離を縮めなければ、視点が壁の向こうへ出て地形や建物がカメラを覆う。
#[test]
fn 壁に遮られると表示距離は壁の手前まで縮む() {
    let (表示距離, 判定) = 決める(&mut 南4メートルに壁のある世界(), 入力(8.0, 前の描画の表示距離::まだ描いていない));
    assert_eq!(判定, 遮蔽の判定::遮られている);
    assert_eq!(表示距離, メートル::生成する(3.75));
}

#[test]
fn 遮るものが無ければ最初の描画は理想距離になる() {
    let (表示距離, 判定) = 決める(&mut 壁の無い世界(), 入力(8.0, 前の描画の表示距離::まだ描いていない));
    assert_eq!(判定, 遮蔽の判定::遮られていない);
    assert_eq!(表示距離, メートル::生成する(8.0));
}

/// 反証: 縮む向きにも復帰の速さを効かせると、壁へ近づいたときに視点が壁の中へ1描画以上残る。
#[test]
fn 縮む向きは即時である() {
    let (表示距離, 判定) = 決める(&mut 南4メートルに壁のある世界(), 入力(8.0, 描いた(8.0, 8.0)));
    assert_eq!(判定, 遮蔽の判定::遮られている);
    assert_eq!(表示距離, メートル::生成する(3.75));
}

/// 反証: 評価できない描画を「何にも触れない」と読むと、未読込の中へ視点が出る。
#[test]
fn 評価できない描画は前の表示距離を保つ() {
    let mut 世界 = 南4メートルに壁のある世界().評価できない領域を東に置く(大域メートル::生成する(0.0));
    let (表示距離, 判定) = 決める(&mut 世界, 入力(8.0, 描いた(2.5, 8.0)));
    assert_eq!(判定, 遮蔽の判定::評価できず前の表示距離を保った);
    assert_eq!(表示距離, メートル::生成する(2.5));
}

/// 反証: 評価できない描画で理想距離の増えたぶんを足すと、前の表示距離より先に未読込や壁が無いと確かめないまま視点を伸ばし、判断10を破る。
#[test]
fn 評価できない描画は理想距離が増えても前の表示距離を伸ばさない() {
    let mut 世界 = 南4メートルに壁のある世界().評価できない領域を東に置く(大域メートル::生成する(0.0));
    let (表示距離, 判定) = 決める(&mut 世界, 入力(9.0, 描いた(2.5, 8.0)));
    assert_eq!(判定, 遮蔽の判定::評価できず前の表示距離を保った);
    assert_eq!(表示距離, メートル::生成する(2.5));
}

#[test]
fn 評価できない描画で理想距離が前の表示距離より短ければ理想距離まで縮む() {
    let mut 世界 = 南4メートルに壁のある世界().評価できない領域を東に置く(大域メートル::生成する(0.0));
    let (表示距離, _) = 決める(&mut 世界, 入力(2.0, 描いた(2.5, 8.0)));
    assert_eq!(表示距離, メートル::生成する(2.0));
}

#[test]
fn 評価できない描画でも理想距離を越えない() {
    let mut 世界 = 壁の無い世界().評価できない領域を東に置く(大域メートル::生成する(0.0));
    let (表示距離, _) = 決める(&mut 世界, 入力(2.0, 描いた(6.0, 6.0)));
    assert_eq!(表示距離, メートル::生成する(2.0));
}

/// 反証: 下限を割ると、視点が注視点へ重なって近クリップ面が注視点を越え、エンジンのカメラが値を拒む。
#[test]
fn 注視点のすぐ後ろの壁でも下限を割らない() {
    let mut 世界 = 壁の無い世界().壁を置く(大域メートル::生成する(0.3));
    let (表示距離, 判定) = 決める(&mut 世界, 入力(8.0, 前の描画の表示距離::まだ描いていない));
    assert_eq!(判定, 遮蔽の判定::遮られている);
    assert_eq!(表示距離, メートル::生成する(0.5));
}
