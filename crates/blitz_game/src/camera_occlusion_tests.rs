//! カメラの遮蔽と復帰の検査。平面と段と壁の世界で、遮蔽があれば表示距離が縮むこと・無ければ一定の速さで戻ること・
//! 縮む向きが即時であること・評価できない描画は前の値を保つこと・下限を割らないことを固定する。
//!
//! 構図は、注視点を東0メートル・天頂1メートル・南0メートルに置き、理想視点を真南へ理想距離だけ離した位置に置く。
//! 壁を南4メートルに置くと、半径0.25メートルの球は南3.75メートルで触れるため、理想距離8メートルなら動けた割合は0.46875である。

use blitz_math::{メートル, 大域メートル, 大域ワールド位置, 秒};

use crate::camera_occlusion::カメラの遮蔽と復帰;
use crate::camera_occlusion_input::遮蔽の判定の入力;
use crate::occlusion_verdict::遮蔽の判定;
use crate::planar_test_world::平面と段と壁の世界;
use crate::previous_display_distance::前の描画の表示距離;

const 一刻み: f32 = 1.0 / 60.0;

fn 注視点() -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(1.0), 大域メートル::生成する(0.0))
}

fn 真南の理想視点(理想距離: f32) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(0.0),
        大域メートル::生成する(1.0),
        大域メートル::生成する(f64::from(理想距離)),
    )
}

fn 入力(理想距離: f32, 前の表示距離: 前の描画の表示距離) -> 遮蔽の判定の入力 {
    遮蔽の判定の入力 {
        注視点: 注視点(),
        理想視点: 真南の理想視点(理想距離),
        理想距離: メートル::生成する(理想距離),
        表示距離の下限: メートル::生成する(0.5),
        前の表示距離,
        進めた時間: 秒::生成する(一刻み),
    }
}

fn 壁の無い世界() -> 平面と段と壁の世界 {
    平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0))
}

fn 南4メートルに壁のある世界() -> 平面と段と壁の世界 {
    壁の無い世界().壁を置く(大域メートル::生成する(4.0))
}

fn 決める(世界: &mut 平面と段と壁の世界, 入力: 遮蔽の判定の入力) -> (メートル, 遮蔽の判定) {
    match カメラの遮蔽と復帰::初版の値で生成する().表示距離を決める(世界, 入力) {
        Ok(決定) => (決定.表示距離(), 決定.判定()),
        Err(誤り) => match 誤り {},
    }
}

/// 反証: 遮蔽で表示距離を縮めなければ、視点が壁の向こうへ出て地形や建物がカメラを覆う。
#[test]
fn 壁に遮られると表示距離は壁の手前まで縮む() {
    let (表示距離, 判定) = 決める(&mut 南4メートルに壁のある世界(), 入力(8.0, 前の描画の表示距離::まだ描いていない));
    assert_eq!(判定, 遮蔽の判定::遮られている);
    assert_eq!(表示距離, メートル::生成する(3.75));
}

#[test]
fn 遮るものが無ければ最初の描画は理想距離になる() {
    let (表示距離, 判定) = 決める(&mut 壁の無い世界(), 入力(8.0, 前の描画の表示距離::まだ描いていない));
    assert_eq!(判定, 遮蔽の判定::遮られていない);
    assert_eq!(表示距離, メートル::生成する(8.0));
}

/// 反証: 遮蔽が消えた瞬間に理想距離へ跳ぶと、視点が不連続に動く。1刻みで伸びるのは毎秒8メートルの1/60である。
#[test]
fn 遮蔽が消えると表示距離は毎秒8メートルで理想距離へ戻る() {
    let (表示距離, 判定) = 決める(&mut 壁の無い世界(), 入力(8.0, 前の描画の表示距離::描いた(メートル::生成する(3.75))));
    assert_eq!(判定, 遮蔽の判定::遮られていない);
    assert_eq!(表示距離, メートル::生成する(3.75) + メートル::生成する(8.0 * 一刻み));
}

#[test]
fn 復帰は理想距離を越えない() {
    let (表示距離, _) = 決める(&mut 壁の無い世界(), 入力(8.0, 前の描画の表示距離::描いた(メートル::生成する(7.95))));
    assert_eq!(表示距離, メートル::生成する(8.0));
}

/// 反証: 縮む向きにも復帰の速さを効かせると、壁へ近づいたときに視点が壁の中へ1描画以上残る。
#[test]
fn 縮む向きは即時である() {
    let (表示距離, 判定) = 決める(
        &mut 南4メートルに壁のある世界(),
        入力(8.0, 前の描画の表示距離::描いた(メートル::生成する(8.0))),
    );
    assert_eq!(判定, 遮蔽の判定::遮られている);
    assert_eq!(表示距離, メートル::生成する(3.75));
}

/// 反証: 評価できない描画を「何にも触れない」と読むと、未読込の中へ視点が出る。
#[test]
fn 評価できない描画は前の表示距離を保つ() {
    let mut 世界 = 南4メートルに壁のある世界().評価できない領域を東に置く(大域メートル::生成する(0.0));
    let (表示距離, 判定) = 決める(&mut 世界, 入力(8.0, 前の描画の表示距離::描いた(メートル::生成する(2.5))));
    assert_eq!(判定, 遮蔽の判定::評価できず前の表示距離を保った);
    assert_eq!(表示距離, メートル::生成する(2.5));
}

#[test]
fn 評価できない描画でも理想距離を越えない() {
    let mut 世界 = 壁の無い世界().評価できない領域を東に置く(大域メートル::生成する(0.0));
    let (表示距離, _) = 決める(&mut 世界, 入力(2.0, 前の描画の表示距離::描いた(メートル::生成する(6.0))));
    assert_eq!(表示距離, メートル::生成する(2.0));
}

/// 反証: 下限を割ると、視点が注視点へ重なって近クリップ面が注視点を越え、エンジンのカメラが値を拒む。
#[test]
fn 注視点のすぐ後ろの壁でも下限を割らない() {
    let mut 世界 = 壁の無い世界().壁を置く(大域メートル::生成する(0.3));
    let (表示距離, 判定) = 決める(&mut 世界, 入力(8.0, 前の描画の表示距離::まだ描いていない));
    assert_eq!(判定, 遮蔽の判定::遮られている);
    assert_eq!(表示距離, メートル::生成する(0.5));
}
