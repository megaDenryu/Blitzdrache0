//! 評価できない領域: 検査用の世界だけが持つ、問い合わせの覆いがそこへ達すると完全性が落ちる領域の枝。担当するのは、
//! 掃引の始まりと終わりの球の覆いがその領域へ達するかの判定である。エンジンの問い合わせが未読込の升目を覆いが含むと
//! 完全性を落とす規律を、平面の世界で真似る。
//!
//! 東の上空だけの枝は、胴体の掃引(上端が足元から0.8メートル)は完全に評価できるが、段差の持ち上げで上へ掃引した胴体
//! (上端が1.1メートル)だけが達する高さに置くための枝である。持ち上げの3件だけが評価できない刻みを検査で作るのに使う。

#[derive(Debug, Clone, Copy)]
pub(super) enum 評価できない領域 {
    無し,
    東の境界より東(f64),
    東の境界より東の上空 { 東: f64, 高さ: f64 },
}

impl 評価できない領域 {
    // 中心の一覧の各球が、始まりか変位だけ進んだ終わりでこの領域へ達するか。球の東と天頂の届く範囲(中心+半径)で判定する。
    pub(super) fn 覆いが達するか(&self, 中心一覧: &[[f64; 3]], 半径: f64, 変位: [f64; 3]) -> bool {
        中心一覧.iter().any(|中心| {
            let 終わり = [中心[0] + 変位[0], 中心[1] + 変位[1], 中心[2] + 変位[2]];
            self.球が達するか(*中心, 半径) || self.球が達するか(終わり, 半径)
        })
    }

    fn 球が達するか(&self, 中心: [f64; 3], 半径: f64) -> bool {
        match *self {
            Self::無し => false,
            Self::東の境界より東(境界) => 中心[0] + 半径 >= 境界,
            Self::東の境界より東の上空 { 東, 高さ } => 中心[0] + 半径 >= 東 && 中心[1] + 半径 >= 高さ,
        }
    }
}
