//! 平面と段と壁の世界へ面を置く組み立ての局面。呼ばれるのは検査が世界を組む最初だけであり、問い合わせに答える局面とは
//! 呼び出しの時期が違う。触れるのは面一覧と稜一覧と評価できない東の境界の3つだけである。

use blitz_math::{ラジアン, 大域メートル};

use super::平面と段と壁の世界;
use crate::crest_edge::水平の稜;
use crate::half_space_face::{半空間の面, 面の範囲};
use crate::horizontal_unit_vector::水平面の単位ベクトル;

impl 平面と段と壁の世界 {
    // 南座標より南を壁にする。壁の面は北を向く。
    pub(crate) fn 壁を置く(mut self, 南座標: 大域メートル) -> Self {
        self.面一覧.push(半空間の面 {
            法線: [0.0, 0.0, -1.0],
            閾値: -南座標.値(),
            範囲: 面の範囲::全域,
        });
        self
    }

    // 東端より東の床を段の上面の高さへ上げ、東端に蹴上げの面を立てる。
    pub(crate) fn 段を置く(mut self, 東端: 大域メートル, 上面の高さ: 大域メートル) -> Self {
        self.面一覧.push(半空間の面 {
            法線: [0.0, 1.0, 0.0],
            閾値: 上面の高さ.値(),
            範囲: 面の範囲::東がこれ以上(東端.値()),
        });
        self.面一覧.push(半空間の面 {
            法線: [-1.0, 0.0, 0.0],
            閾値: -東端.値(),
            範囲: 面の範囲::天頂がこれ以下(上面の高さ.値()),
        });
        self
    }

    // 東端より東だけで有効な高い床を置く。蹴上げを立てないため、崖から落ちる検査に使う。
    pub(crate) fn 東側だけ高い床を置く(mut self, 東端: 大域メートル, 高さ: 大域メートル) -> Self {
        self.面一覧.push(半空間の面 {
            法線: [0.0, 1.0, 0.0],
            閾値: 高さ.値(),
            範囲: 面の範囲::東がこれ以上(東端.値()),
        });
        self
    }

    // 原点を通り東へ登る斜面を置く。角は水平から測り、法線は西上向きである。原点より西では床の下に沈む。
    pub(crate) fn 東へ登る斜面を置く(mut self, 水平からの角: ラジアン) -> Self {
        self.面一覧.push(半空間の面 {
            法線: [-f64::from(水平からの角.値().sin()), f64::from(水平からの角.値().cos()), 0.0],
            閾値: 0.0,
            範囲: 面の範囲::全域,
        });
        self
    }

    // 東端の床の高さから東へ下る斜面を、東端より東だけに置き、床と斜面が出会う水平の稜を東端に立てる。
    // 角は水平から測り、法線は東上向きである。西側だけ床の世界と組み合わせて稜を作る。
    pub(crate) fn 東端から東へ下る斜面を置く(
        mut self, 東端: 大域メートル, 床の高さ: 大域メートル, 水平からの角: ラジアン
    ) -> Self {
        let 法線 = [f64::from(水平からの角.値().sin()), f64::from(水平からの角.値().cos()), 0.0];
        self.面一覧.push(半空間の面 {
            法線,
            閾値: 法線[0] * 東端.値() + 法線[1] * 床の高さ.値(),
            範囲: 面の範囲::東がこれ以上(東端.値()),
        });
        self.稜一覧.push(水平の稜 {
            東: 東端.値(),
            高さ: 床の高さ.値(),
        });
        self
    }

    // 内向き(自由側)の水平の向きと、面の上の1点の水平位置で決まる鉛直の壁を置く。2枚を置けば任意の角の内角ができる。
    pub(crate) fn 鉛直の壁を置く(
        mut self, 内向き: 水平面の単位ベクトル, 面の上の東: 大域メートル, 面の上の南: 大域メートル
    ) -> Self {
        let 法線 = [f64::from(内向き.東成分()), 0.0, f64::from(内向き.南成分())];
        self.面一覧.push(半空間の面 {
            法線,
            閾値: 法線[0] * 面の上の東.値() + 法線[2] * 面の上の南.値(),
            範囲: 面の範囲::全域,
        });
        self
    }

    pub(crate) fn 評価できない領域を東に置く(mut self, 東の境界: 大域メートル) -> Self {
        self.評価できない東の境界 = Some(東の境界.値());
        self
    }
}
