//! 平面と段と壁の世界へ面を置く組み立ての局面。呼ばれるのは検査が世界を組む最初だけであり、問い合わせに答える局面とは
//! 呼び出しの時期が違う。触れるのは面一覧と評価できない東の境界の2つだけである。

use blitz_math::{ラジアン, 大域メートル};

use super::平面と段と壁の世界;
use crate::half_space_face::{半空間の面, 面の範囲};

impl 平面と段と壁の世界 {
    /// 南座標より南を壁にする。壁の面は北を向く。
    pub(crate) fn 壁を置く(mut self, 南座標: 大域メートル) -> Self {
        self.面一覧.push(半空間の面 {
            法線: [0.0, 0.0, -1.0],
            閾値: -南座標.値(),
            範囲: 面の範囲::全域,
        });
        self
    }

    /// 東端より東の床を段の上面の高さへ上げ、東端に蹴上げの面を立てる。
    pub(crate) fn 段を置く(mut self, 東端: 大域メートル, 上面の高さ: 大域メートル) -> Self {
        self.面一覧.push(半空間の面 {
            法線: [0.0, 1.0, 0.0],
            閾値: 上面の高さ.値(),
            範囲: 面の範囲::東がこれ以上(東端.値()),
        });
        self.面一覧.push(半空間の面 {
            法線: [-1.0, 0.0, 0.0],
            閾値: -東端.値(),
            範囲: 面の範囲::天頂がこれ以下(上面の高さ.値()),
        });
        self
    }

    /// 東端より東だけで有効な高い床を置く。蹴上げを立てないため、崖から落ちる検査に使う。
    pub(crate) fn 東側だけ高い床を置く(mut self, 東端: 大域メートル, 高さ: 大域メートル) -> Self {
        self.面一覧.push(半空間の面 {
            法線: [0.0, 1.0, 0.0],
            閾値: 高さ.値(),
            範囲: 面の範囲::東がこれ以上(東端.値()),
        });
        self
    }

    /// 原点を通り東へ登る斜面を置く。角は水平から測り、法線は西上向きである。原点より西では床の下に沈む。
    pub(crate) fn 東へ登る斜面を置く(mut self, 水平からの角: ラジアン) -> Self {
        self.面一覧.push(半空間の面 {
            法線: [-f64::from(水平からの角.値().sin()), f64::from(水平からの角.値().cos()), 0.0],
            閾値: 0.0,
            範囲: 面の範囲::全域,
        });
        self
    }

    pub(crate) fn 評価できない領域を東に置く(mut self, 東の境界: 大域メートル) -> Self {
        self.評価できない東の境界 = Some(東の境界.値());
        self
    }
}
