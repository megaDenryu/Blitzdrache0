//! 平面と段と壁の世界へ、段差の検査に要る形(段・蹴上げと縁・南端で終わる段・天井・段の先に登る斜面)を置く組み立ての局面。
//! 壁と床と斜面と評価できない領域を置く組み立ては`builders`にある。呼ばれるのは検査が世界を組む最初だけである。
//!
//! 蹴上げの上の縁に水平の稜を立てるのは、球が段の上面へ届く前に縁へ触れる接触を、半空間の面(自分の範囲の外の接触を
//! 持たない)が答えられないためである。実際の地形と建物の三角形が凸の縁で持つ接触と同じ形であり、段差の持ち上げの
//! 下へ掃引した先が縁になる場合をこの稜が作る。

use blitz_math::{ラジアン, 大域メートル};

use super::平面と段と壁の世界;
use crate::crest_edge::水平の稜;
use crate::half_space_face::{半空間の面, 面の範囲};

impl 平面と段と壁の世界 {
    // 東端より東の床を段の上面の高さへ上げ、東端に蹴上げの面と縁の稜を立てる。
    pub(crate) fn 段を置く(mut self, 東端: 大域メートル, 上面の高さ: 大域メートル) -> Self {
        self.面一覧.push(半空間の面 {
            法線: [0.0, 1.0, 0.0],
            閾値: 上面の高さ.値(),
            範囲: 面の範囲::東がこれ以上(東端.値()),
        });
        self.蹴上げを置く(東端, 上面の高さ)
    }

    // 東端に、上面の高さより下だけで有効な西向きの蹴上げの面と、蹴上げの上の縁の稜を立てる。上面は置かない。
    pub(crate) fn 蹴上げを置く(mut self, 東端: 大域メートル, 上面の高さ: 大域メートル) -> Self {
        self.面一覧.push(半空間の面 {
            法線: [-1.0, 0.0, 0.0],
            閾値: -東端.値(),
            範囲: 面の範囲::天頂がこれ以下(上面の高さ.値()),
        });
        self.稜一覧.push(水平の稜 {
            東: 東端.値(),
            高さ: 上面の高さ.値(),
            範囲: 面の範囲::全域,
        });
        self
    }

    // 東端より東で南端より北だけにある段(上面・蹴上げ・縁の稜)を置く。南端より南は元の床のままであり、段の南の側面は置かない。
    // 段の角を斜めに抜けて元の床へ降りる検査が使う。
    pub(crate) fn 南端までの段を置く(
        mut self, 東端: 大域メートル, 上面の高さ: 大域メートル, 南端: 大域メートル
    ) -> Self {
        self.面一覧.push(半空間の面 {
            法線: [0.0, 1.0, 0.0],
            閾値: 上面の高さ.値(),
            範囲: 面の範囲::東がこれ以上で南がこれ以下 {
                東端: 東端.値(),
                南端: 南端.値(),
            },
        });
        self.面一覧.push(半空間の面 {
            法線: [-1.0, 0.0, 0.0],
            閾値: -東端.値(),
            範囲: 面の範囲::天頂がこれ以下で南がこれ以下 {
                上面: 上面の高さ.値(),
                南端: 南端.値(),
            },
        });
        self.稜一覧.push(水平の稜 {
            東: 東端.値(),
            高さ: 上面の高さ.値(),
            範囲: 面の範囲::南がこれ以下(南端.値()),
        });
        self
    }

    // 南端より南だけで有効な床を置く。南端までの段と組み合わせ、段の角を抜けた先の床を元の床よりわずかに高くする検査に使う。
    pub(crate) fn 南端より南の床を置く(mut self, 南端: 大域メートル, 高さ: 大域メートル) -> Self {
        self.面一覧.push(半空間の面 {
            法線: [0.0, 1.0, 0.0],
            閾値: 高さ.値(),
            範囲: 面の範囲::南がこれ以上(南端.値()),
        });
        self
    }

    // 東端の足元の高さから東へ登る斜面を、東端より東だけに置く。角は水平から測り、法線は西上向きである。
    // 蹴上げと組み合わせると、段を越えた先が斜面になる。
    pub(crate) fn 東端から東へ登る斜面を置く(
        mut self, 東端: 大域メートル, 足元の高さ: 大域メートル, 水平からの角: ラジアン
    ) -> Self {
        let 法線 = [-f64::from(水平からの角.値().sin()), f64::from(水平からの角.値().cos()), 0.0];
        self.面一覧.push(半空間の面 {
            法線,
            閾値: 法線[0] * 東端.値() + 法線[1] * 足元の高さ.値(),
            範囲: 面の範囲::東がこれ以上(東端.値()),
        });
        self
    }

    // 全域に下向きの天井を置く。天井の面は下を向く。
    pub(crate) fn 天井を置く(mut self, 高さ: 大域メートル) -> Self {
        self.面一覧.push(半空間の面 {
            法線: [0.0, -1.0, 0.0],
            閾値: -高さ.値(),
            範囲: 面の範囲::全域,
        });
        self
    }
}
