//! 共通入力層とゲームロジック層の境界の型を所有する。この型の値は、共通入力層がデバイスの入力を整えて作るほか、
//! 決まった手順の操作(`blitz_app` の `world_execution/game/操作の台本.rs`)がデバイスを通らずに組み立てることもある。
//! どちらの出どころでも、デバイスの種類(キーボード・パッド)はこの型より手前で消えており、ここから先はどの操作が押されているかだけが残る。
//! 参照: `_doc/計画/ユビキタス言語.md`「ゲームの操作意図」。

#[path = "確定済みの入力/押した瞬間の操作.rs"]
mod 押した瞬間の操作;
#[path = "確定済みの入力/押下が続く操作.rs"]
mod 押下が続く操作;

use blitz_design::{M不変データ, M中間入力, M解釈前の入力};

pub use self::押した瞬間の操作::押した瞬間の操作の入力;
pub use self::押下が続く操作::押下が続く操作の入力;

/// 1フレームぶんを確定した、デバイスに依らない操作の入力。入力の出どころに依らない形(押した瞬間を判定した形)へ整えた値であり、
/// まだゲームの意味を持たないため、`M解釈前の入力` のうち `M中間入力` を名乗る。誰が作ったか(共通入力層か決まった手順の操作か)によらず、この形であることで決まる。
///
/// 操作を、押下が続く間ずっと意味を持つもの(移動の4つと走る)と、押した瞬間だけ意味を持つもの(決定・キャンセル・ジャンプ・カメラの系統の切替)の2つの値に分けて持つ。
/// 1描画で複数の固定刻みを進める実行は、押した瞬間の操作だけを落とすため、この境界で値が分かれる(`押した瞬間の操作を落とした入力`)。
/// カメラの系統の切替はゲームの意図へ写されず、コンポジションルートのゲーム配線が描画機会ごとに消費する。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 確定済みの操作入力 {
    押下が続く操作: 押下が続く操作の入力,
    押した瞬間の操作: 押した瞬間の操作の入力,
}

impl M不変データ for 確定済みの操作入力 {}
impl M解釈前の入力 for 確定済みの操作入力 {}
impl M中間入力 for 確定済みの操作入力 {}

impl 確定済みの操作入力 {
    pub fn 生成する(押下が続く操作: 押下が続く操作の入力, 押した瞬間の操作: 押した瞬間の操作の入力) -> Self {
        Self {
            押下が続く操作, 押した瞬間の操作
        }
    }

    /// どの操作も押されていない入力。
    pub fn 無操作() -> Self {
        Self::default()
    }

    /// 押した瞬間の操作(決定・キャンセル・ジャンプ・カメラの系統の切替)だけを落とし、押下が続く操作はそのまま残した入力。
    ///
    /// 1描画で複数の固定刻みを進める実行が使う。押した瞬間の操作を全ての刻みへ同じ値で渡すと、
    /// 1回の押し下げが刻みの本数だけ発火する。
    pub fn 押した瞬間の操作を落とした入力(&self) -> Self {
        Self::生成する(self.押下が続く操作, 押した瞬間の操作の入力::無操作())
    }

    pub fn 押下が続く操作(&self) -> 押下が続く操作の入力 {
        self.押下が続く操作
    }

    pub fn 押した瞬間の操作(&self) -> 押した瞬間の操作の入力 {
        self.押した瞬間の操作
    }
}
