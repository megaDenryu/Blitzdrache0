//! 進行段階の移り方の検査。正しい遷移が起きることと、起きてはならない遷移が起きないことの両方を見る。

use crate::game_intent::ゲームインテント;
use crate::progress_stage::{ゲームの進行段階, 終了確認から戻る段階};

fn 決定だけのインテント() -> ゲームインテント {
    ゲームインテント {
        決定を押したか: true,
        ..ゲームインテント::無操作()
    }
}

fn キャンセルだけのインテント() -> ゲームインテント {
    ゲームインテント {
        キャンセルを押したか: true,
        ..ゲームインテント::無操作()
    }
}

#[test]
fn タイトルで決定すると場所巡りへ移る() {
    let 次 = ゲームの進行段階::タイトル表示中.次の段階を決める(決定だけのインテント());
    assert_eq!(次, ゲームの進行段階::場所巡り中);
}

#[test]
fn タイトルでキャンセルするとタイトルへ戻る終了確認になる() {
    let 次 = ゲームの進行段階::タイトル表示中.次の段階を決める(キャンセルだけのインテント());
    assert_eq!(
        次,
        ゲームの進行段階::終了確認中 {
            取り消したときに戻る段階: 終了確認から戻る段階::タイトル表示中
        }
    );
}

#[test]
fn 場所巡り中のキャンセルは場所巡りへ戻る終了確認になる() {
    let 次 = ゲームの進行段階::場所巡り中.次の段階を決める(キャンセルだけのインテント());
    assert_eq!(
        次,
        ゲームの進行段階::終了確認中 {
            取り消したときに戻る段階: 終了確認から戻る段階::場所巡り中
        }
    );
}

/// 反証: 場所巡り中の決定でも段階が変わると、遊んでいる最中に別の画面へ飛ぶ。
#[test]
fn 場所巡り中に決定しても段階は変わらない() {
    let 次 = ゲームの進行段階::場所巡り中.次の段階を決める(決定だけのインテント());
    assert_eq!(次, ゲームの進行段階::場所巡り中);
}

#[test]
fn 終了確認で決定すると終了決定済みになる() {
    let 確認中 = ゲームの進行段階::終了確認中 {
        取り消したときに戻る段階: 終了確認から戻る段階::場所巡り中,
    };
    assert_eq!(確認中.次の段階を決める(決定だけのインテント()), ゲームの進行段階::終了決定済み);
}

#[test]
fn 終了確認を取り消すと開いた元の段階へ戻る() {
    let 確認中 = ゲームの進行段階::終了確認中 {
        取り消したときに戻る段階: 終了確認から戻る段階::タイトル表示中,
    };
    assert_eq!(確認中.次の段階を決める(キャンセルだけのインテント()), ゲームの進行段階::タイトル表示中);
}

/// 反証: 決定とキャンセルが同じフレームに届いたとき決定が勝つと、取り消したはずの操作でゲームが閉じる。
#[test]
fn 終了確認で決定とキャンセルが同時なら取り消しが勝つ() {
    let 確認中 = ゲームの進行段階::終了確認中 {
        取り消したときに戻る段階: 終了確認から戻る段階::場所巡り中,
    };
    let 両方 = ゲームインテント {
        決定を押したか: true,
        キャンセルを押したか: true,
        ..ゲームインテント::無操作()
    };
    assert_eq!(確認中.次の段階を決める(両方), ゲームの進行段階::場所巡り中);
}

/// 反証: 終了決定済みから戻れると、閉じる途中のフレームの操作で終了が取り消される。
#[test]
fn 終了決定済みはどの操作でも変わらない() {
    assert_eq!(
        ゲームの進行段階::終了決定済み.次の段階を決める(キャンセルだけのインテント()),
        ゲームの進行段階::終了決定済み
    );
    assert_eq!(
        ゲームの進行段階::終了決定済み.次の段階を決める(決定だけのインテント()),
        ゲームの進行段階::終了決定済み
    );
}
