//! 進行段階の移り方の検査。正しい遷移が起きることと、起きてはならない遷移が起きないことの両方を見る。

use crate::confirmed_input::{押した瞬間の操作の入力, 押下が続く操作の入力, 確定済みの操作入力};
use crate::progress_stage::{ゲームの進行段階, 終了確認から戻る段階};
use crate::操作意図の命令::進行の操作;

#[test]
fn タイトルで決定すると場所巡りへ移る() {
    let 次 = ゲームの進行段階::タイトル表示中.次の段階を決める(進行の操作::決定する);
    assert_eq!(次, ゲームの進行段階::場所巡り中);
}

#[test]
fn タイトルでキャンセルするとタイトルへ戻る終了確認になる() {
    let 次 = ゲームの進行段階::タイトル表示中.次の段階を決める(進行の操作::取り消す);
    assert_eq!(
        次,
        ゲームの進行段階::終了確認中 {
            取り消したときに戻る段階: 終了確認から戻る段階::タイトル表示中
        }
    );
}

#[test]
fn 場所巡り中のキャンセルは場所巡りへ戻る終了確認になる() {
    let 次 = ゲームの進行段階::場所巡り中.次の段階を決める(進行の操作::取り消す);
    assert_eq!(
        次,
        ゲームの進行段階::終了確認中 {
            取り消したときに戻る段階: 終了確認から戻る段階::場所巡り中
        }
    );
}

/// 反証: 場所巡り中の決定でも段階が変わると、遊んでいる最中に別の画面へ飛ぶ。
#[test]
fn 場所巡り中に決定しても段階は変わらない() {
    let 次 = ゲームの進行段階::場所巡り中.次の段階を決める(進行の操作::決定する);
    assert_eq!(次, ゲームの進行段階::場所巡り中);
}

#[test]
fn 終了確認で決定すると終了決定済みになる() {
    let 確認中 = ゲームの進行段階::終了確認中 {
        取り消したときに戻る段階: 終了確認から戻る段階::場所巡り中,
    };
    assert_eq!(確認中.次の段階を決める(進行の操作::決定する), ゲームの進行段階::終了決定済み);
}

#[test]
fn 終了確認を取り消すと開いた元の段階へ戻る() {
    let 確認中 = ゲームの進行段階::終了確認中 {
        取り消したときに戻る段階: 終了確認から戻る段階::タイトル表示中,
    };
    assert_eq!(確認中.次の段階を決める(進行の操作::取り消す), ゲームの進行段階::タイトル表示中);
}

/// 反証: 決定とキャンセルが同じ刻みに届いたとき決定が勝つと、取り消したはずの操作でゲームが閉じる。
/// 優先は進行の操作への解釈が決めるため、確定済みの操作入力から解釈を通して遷移させる。
#[test]
fn 終了確認で決定とキャンセルが同時なら取り消しが勝つ() {
    let 確認中 = ゲームの進行段階::終了確認中 {
        取り消したときに戻る段階: 終了確認から戻る段階::場所巡り中,
    };
    let 両方 = 確定済みの操作入力::生成する(
        押下が続く操作の入力::無操作(),
        押した瞬間の操作の入力::無操作().決定操作を押した瞬間かを置き換えた入力(true).取り消し操作を押した瞬間かを置き換えた入力(true),
    );
    let 操作 = 進行の操作::確定済みの操作入力から解釈する(&両方);
    assert_eq!(操作, 進行の操作::取り消す);
    assert_eq!(確認中.次の段階を決める(操作), ゲームの進行段階::場所巡り中);
}

/// 反証: 終了決定済みから戻れると、閉じる途中のフレームの操作で終了が取り消される。
#[test]
fn 終了決定済みはどの操作でも変わらない() {
    assert_eq!(ゲームの進行段階::終了決定済み.次の段階を決める(進行の操作::取り消す), ゲームの進行段階::終了決定済み);
    assert_eq!(ゲームの進行段階::終了決定済み.次の段階を決める(進行の操作::決定する), ゲームの進行段階::終了決定済み);
}
