//! 掃引の接触: 掃引した形が世界の形に最初に触れた1つの事実。動けた割合・接触の大域位置・接触の単位法線の3つを持つ。
//!
//! 地形か建物かの区別と、どの升目・どの子形状かの所在を持たないのは、ゲームの意味付け(地面・壁・カメラを遮る物)が
//! この3つだけで決まるためである。要る日が来たらこの型へ足す。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断3」

use blitz_math::{ワールド, 大域ワールド位置, 方向};

use crate::moved_fraction::動けた割合;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 掃引の接触 {
    動けた割合: 動けた割合,
    接触の大域位置: 大域ワールド位置,
    接触の単位法線: 方向<ワールド>,
}

impl 掃引の接触 {
    pub fn 生成する(
        動けた割合: 動けた割合, 接触の大域位置: 大域ワールド位置, 接触の単位法線: 方向<ワールド>
    ) -> Self {
        Self {
            動けた割合,
            接触の大域位置,
            接触の単位法線,
        }
    }

    /// 掃引の変位のうち、触れるまでに動けた分の割合。動く前から触れていた場合は0である。
    pub fn 動けた割合(&self) -> 動けた割合 {
        self.動けた割合
    }

    pub fn 接触の大域位置(&self) -> 大域ワールド位置 {
        self.接触の大域位置
    }

    /// 接触の点から掃引した形の内側へ向かう単位方向。面に触れたときはその面の法線と同じである。
    pub fn 接触の単位法線(&self) -> 方向<ワールド> {
        self.接触の単位法線
    }
}
