//! 掃引の答えの完全性。世界側の問い合わせ完全性をゲームロジック層の語彙へ1対1で写した枝である。
//!
//! 当たりの有無と別の軸に置くのは、「何にも触れなかった」と「調べられなかったので分からない」を別の事実として
//! 扱うためである。評価できない領域を含む答えは「この範囲に当たりは無い」ではなく「打ち切りより先は分からない」と読む。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断8」

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 掃引の完全性 {
    対象範囲を完全に評価できた, // 答えを出すのに要る範囲を調べ切ったため、答えは確定的である
    評価できない領域を含む,     // 未読込の区域か世界の形の広がりの外で止めたため、答えは確定的でない
}
