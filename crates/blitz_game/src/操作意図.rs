//! ゲームロジック層が消費する操作の意図と、確定済みの操作入力からそこへの写像を所有する。
//!
//! 写像をゲーム側へ置くのは、どの操作がどんな意味を持つかがゲームごとに変わるためである。共通入力層が担うのは
//! デバイスからデバイス非依存の入力までの段であり、その先の意味付けがこの写像である(判断3の2段構え)。
//! 意図は、読む処理ごとに分けた2つの命令(`操作意図の命令`)を組にし、固定刻みの処理位置のあいだを運ぶ `M値オブジェクト` であり、写像は命令ごとの解釈を呼んで組む。
//! 意図を読む処理(進行段階の遷移・胴体の移動)は意図を丸ごと受け取らず、コンポジションルートの配線が取り出した自分の命令だけを受け取る。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断3」。

use blitz_design::{M不変データ, M値オブジェクト};

use crate::操作意図の命令::{胴体の移動の操作, 進行の操作};
use crate::確定済みの入力::確定済みの操作入力;

/// 1刻みぶんのゲームの操作意図。進行段階の遷移が読む進行の操作と、胴体の移動の遷移が読む胴体の移動の操作の2つである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ゲームの操作意図 {
    進行の操作: 進行の操作,
    胴体の移動の操作: 胴体の移動の操作,
}

impl M不変データ for ゲームの操作意図 {}
impl M値オブジェクト for ゲームの操作意図 {}

impl ゲームの操作意図 {
    pub fn 生成する(進行の操作: 進行の操作, 胴体の移動の操作: 胴体の移動の操作) -> Self {
        Self { 進行の操作, 胴体の移動の操作 }
    }

    /// 何も操作しなかった刻みの意図。
    pub fn 無操作() -> Self {
        Self::生成する(進行の操作::何もしない, 胴体の移動の操作::何もしない())
    }

    /// 確定済みの操作入力を、命令ごとの解釈でこのゲームでの意味へ写す。
    pub fn 確定済みの操作入力から写す(入力: 確定済みの操作入力) -> Self {
        Self::生成する(進行の操作::確定済みの操作入力から解釈する(&入力), 胴体の移動の操作::確定済みの操作入力から解釈する(&入力))
    }

    pub fn 進行の操作(&self) -> 進行の操作 {
        self.進行の操作
    }

    pub fn 胴体の移動の操作(&self) -> 胴体の移動の操作 {
        self.胴体の移動の操作
    }
}
