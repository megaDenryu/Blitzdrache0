//! ゲームロジック層が消費する操作の意図と、確定済みの操作入力からそこへの写像を所有する。
//!
//! 写像をゲーム側へ置くのは、どの操作がどんな意味を持つかがゲームごとに変わるためである。共通入力層が担うのは
//! デバイスからデバイス非依存の入力までの段であり、その先の意味付けがこの写像である(判断3の2段構え)。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断3」。

use crate::confirmed_input::確定済みの操作入力;
use crate::operation_axis::操作軸の倒し量;

/// 1フレームぶんのゲームの操作意図。移動2成分・決定・キャンセルに、胴体の移動のジャンプと走るを加えた6つである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ゲームインテント {
    pub 前後の倒し量: 操作軸の倒し量, // 正が前(北へ向かう向き)
    pub 左右の倒し量: 操作軸の倒し量, // 正が右(東へ向かう向き)
    pub 決定を押したか: bool,
    pub キャンセルを押したか: bool,
    pub ジャンプしたいか: bool, // 押した瞬間の操作であり、接地中の刻みにだけ意味を持つ
    pub 走りたいか: bool,       // 押下が続く操作であり、接地中の速さを歩くから走るへ変える
}

impl ゲームインテント {
    /// 何も操作しなかったフレームの意図。
    pub fn 無操作() -> Self {
        Self {
            前後の倒し量: 操作軸の倒し量::中立(),
            左右の倒し量: 操作軸の倒し量::中立(),
            決定を押したか: false,
            キャンセルを押したか: false,
            ジャンプしたいか: false,
            走りたいか: false,
        }
    }

    /// 確定済みの操作入力を、このゲームでの意味へ写す。
    pub fn 確定済みの操作入力から写す(入力: 確定済みの操作入力) -> Self {
        Self {
            前後の倒し量: 操作軸の倒し量::押下の対から生成する(
                入力.前へ進む操作を押しているか,
                入力.後ろへ下がる操作を押しているか,
            ),
            左右の倒し量: 操作軸の倒し量::押下の対から生成する(
                入力.右へ寄る操作を押しているか,
                入力.左へ寄る操作を押しているか,
            ),
            決定を押したか: 入力.決定操作を押した瞬間か,
            キャンセルを押したか: 入力.取り消し操作を押した瞬間か,
            ジャンプしたいか: 入力.ジャンプ操作を押した瞬間か,
            走りたいか: 入力.走る操作を押しているか,
        }
    }
}
