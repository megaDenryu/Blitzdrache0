//! 表示距離の決定: 前の描画の表示距離の遷移が1描画に1度観測として返す、表示距離とその判定の対。
//! 状態の正本ではなく、エンジンのカメラへ据える距離と計器の判定を外へ渡すために導いた値であるため `M観測` を名乗る。

use blitz_design::{M不変データ, M値オブジェクト, M観測};
use blitz_math::メートル;

use crate::遮蔽の判定の選択肢::遮蔽の判定;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 表示距離の決定 {
    表示距離: メートル,
    判定: 遮蔽の判定,
}

impl M不変データ for 表示距離の決定 {}
impl M値オブジェクト for 表示距離の決定 {}
impl M観測 for 表示距離の決定 {}

impl 表示距離の決定 {
    pub(crate) fn 生成する(表示距離: メートル, 判定: 遮蔽の判定) -> Self {
        Self { 表示距離, 判定 }
    }

    /// エンジンのカメラへ据える距離。理想距離を越えず、表示距離の下限を割らない。
    pub fn 表示距離(&self) -> メートル {
        self.表示距離
    }

    pub fn 判定(&self) -> 遮蔽の判定 {
        self.判定
    }
}
