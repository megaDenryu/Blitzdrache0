//! 前の描画の表示距離: 復帰の速さを効かせる基準と、評価できない描画で保つ値を運ぶ枝。表示距離と一緒に、
//! それを決めたときの理想距離を持つ。
//!
//! まだ1度も描いていない状態を枝で持つのは、最初の描画に基準が無いことを距離の値に密輸しないためである。
//! 最初の描画は理想距離を基準にし、遮られていればそこから即時に縮む。
//!
//! 基準に理想距離の増えたぶんを足すのは、利用者のズームアウト(理想距離の増加)を即時に通し、遮蔽からの回復だけを
//! 復帰の速さで遅らせるためである。前の表示距離をそのまま基準にすると、遮蔽が無くてもズームアウトが復帰の速さで遅れる。
//! 減ったぶんを基準から引かないのは、遮蔽で縮んでいる間のズームインで基準が遮蔽の許す距離より縮み、そこから復帰の速さで戻る揺れを作らないためである。
//! ズームインの即時性は、基準を今の理想距離で切り詰めることと、目標が基準以下なら即時に目標へ縮むことで守られる。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断10」「進行の記録」2026-09-02のレビュー是正

use blitz_math::メートル;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 前の描画の表示距離 {
    まだ描いていない,
    描いた {
        表示距離: メートル,
        理想距離: メートル,
    },
}

impl 前の描画の表示距離 {
    /// 復帰と保持の基準にする距離。前の表示距離に理想距離の増えたぶんを足し、表示距離の下限で切り上げてから今の理想距離で切り詰める。
    /// まだ描いていなければ今の理想距離を基準にする。
    pub(crate) fn 基準にする距離(self, 今の理想距離: メートル, 表示距離の下限: メートル) -> メートル {
        match self {
            Self::まだ描いていない => 今の理想距離,
            Self::描いた { 表示距離, 理想距離 } => {
                let 変化を足した距離 = if 今の理想距離 > 理想距離 {
                    表示距離 + (今の理想距離 - 理想距離)
                } else {
                    表示距離
                };
                let 下限で切り上げた距離 = if 変化を足した距離 < 表示距離の下限 {
                    表示距離の下限
                } else {
                    変化を足した距離
                };
                if 下限で切り上げた距離 > 今の理想距離 {
                    今の理想距離
                } else {
                    下限で切り上げた距離
                }
            }
        }
    }
}
