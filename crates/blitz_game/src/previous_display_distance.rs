//! 前の描画の表示距離: 復帰の速さを効かせる基準と、評価できない描画で保つ値を運ぶ枝。
//!
//! まだ1度も描いていない状態を枝で持つのは、最初の描画に基準が無いことを距離の値に密輸しないためである。
//! 最初の描画は理想距離を基準にし、遮られていればそこから即時に縮む。

use blitz_math::メートル;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 前の描画の表示距離 {
    まだ描いていない,
    描いた(メートル),
}

impl 前の描画の表示距離 {
    /// 復帰と保持の基準にする距離。まだ描いていなければ理想距離を基準にする。
    pub(crate) fn 基準にする距離(self, 理想距離: メートル) -> メートル {
        match self {
            Self::まだ描いていない => 理想距離,
            Self::描いた(表示距離) => 表示距離,
        }
    }
}
