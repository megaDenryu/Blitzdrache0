//! 半空間の面: 検査用の世界を組む1枚の面。自由側を向く単位法線と閾値で決まる半空間であり、東または天頂の範囲で
//! 有効な部分を限れる。担当するのは、球がこの面へ触れる時刻と、その接触を掃引の接触へ写すことである。
//! どの面をどう並べて世界にするかは`planar_test_world`が持つ。
//!
//! 接触は面へ向かう掃引だけが持つ。エンジンの掃引と同じ規則であり、面へ近づく速さが変位の長さの2の20乗分の1に
//! 満たない掃引は平行として触れない。幅の正本は`crates/blitz_collision/src/solver/approach.rs`である。

use blitz_math::{大域メートル, 大域ワールド位置, 方向};

use crate::moved_fraction::動けた割合;
use crate::sweep_contact::掃引の接触;

pub(super) const 平行とみなす余弦の幅: f64 = 9.5367431640625e-7; // 2の20乗分の1。正本はblitz_collisionのsolver/approach.rsであり、conformが突き合わせる

#[derive(Debug, Clone, Copy)]
pub(super) enum 面の範囲 {
    全域,
    東がこれ以上(f64),
    東がこれ以下(f64),
    天頂がこれ以下(f64),
}

#[derive(Debug, Clone, Copy)]
pub(super) struct 半空間の面 {
    pub(super) 法線: [f64; 3], // 自由側を向く単位法線(東・天頂・南)
    pub(super) 閾値: f64,      // 法線と位置の内積がこの値以上なら自由側
    pub(super) 範囲: 面の範囲,
}

impl 半空間の面 {
    /// 球の中心が始点から変位だけ動くとき、この面へ触れる時刻。面へ向かわない掃引と範囲の外の接触は値なしである。
    /// 零の変位は始めから触れている事実を時刻0で返す。
    pub(super) fn 球が触れる時刻(&self, 中心: [f64; 3], 半径: f64, 変位: [f64; 3]) -> Option<f64> {
        let 始めの隙間 = 内積(self.法線, 中心) - self.閾値 - 半径;
        let 近づく速さ = -内積(self.法線, 変位);
        let 面へ向かう = 近づく速さ > 平行とみなす余弦の幅 * 内積(変位, 変位).sqrt();
        let 時刻 = if 始めの隙間 <= 0.0 && (面へ向かう || 内積(変位, 変位) == 0.0) {
            0.0
        } else if 面へ向かう && 0.0 < 始めの隙間 && 始めの隙間 <= 近づく速さ {
            始めの隙間 / 近づく速さ
        } else {
            return None;
        };
        self.範囲の内側か(self.接触点(進めた点(中心, 変位, 時刻), 半径)).then_some(時刻)
    }

    // 範囲を判定するのは接触点であって球の中心ではない。傾いた面では2点の東と天頂が法線×半径だけ違い、中心で判定すると
    // 面が範囲の外へ半径ぶん張り出した形になる(段の縁の稜が答えるべき接触を面が先に答える)。
    fn 接触点(&self, 触れた中心: [f64; 3], 半径: f64) -> [f64; 3] {
        [
            触れた中心[0] - self.法線[0] * 半径,
            触れた中心[1] - self.法線[1] * 半径,
            触れた中心[2] - self.法線[2] * 半径,
        ]
    }

    fn 範囲の内側か(&self, 点: [f64; 3]) -> bool {
        match self.範囲 {
            面の範囲::全域 => true,
            面の範囲::東がこれ以上(東端) => 点[0] >= 東端,
            面の範囲::東がこれ以下(東端) => 点[0] <= 東端,
            面の範囲::天頂がこれ以下(上面) => 点[1] <= 上面,
        }
    }

    /// 触れた時刻の球の表面のうち面へ最も近い点を接触の位置にする。時刻は`球が触れる時刻`が0以上1以下で返した値である。
    pub(super) fn 接触を組む(&self, 時刻: f64, 中心: [f64; 3], 半径: f64, 変位: [f64; 3]) -> 掃引の接触 {
        let 接触点 = self.接触点(進めた点(中心, 変位, 時刻), 半径);
        let 割合 = 動けた割合::倍精度から生成する(時刻)
            .unwrap_or_else(|誤り| panic!("面へ触れる時刻が動けた割合の範囲を外れた(不変条件が破れている): {誤り}"));
        let 法線 = 方向::倍精度の成分から生成する(self.法線[0], self.法線[1], self.法線[2])
            .unwrap_or_else(|誤り| panic!("面の法線が単位方向でない(不変条件が破れている): {誤り}"));
        掃引の接触::生成する(割合, 大域位置(接触点), 法線)
    }
}

pub(super) fn 内積(左: [f64; 3], 右: [f64; 3]) -> f64 {
    左[0] * 右[0] + 左[1] * 右[1] + 左[2] * 右[2]
}

pub(super) fn 進めた点(点: [f64; 3], 変位: [f64; 3], 時刻: f64) -> [f64; 3] {
    [点[0] + 変位[0] * 時刻, 点[1] + 変位[1] * 時刻, 点[2] + 変位[2] * 時刻]
}

pub(super) fn 大域位置(成分: [f64; 3]) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(成分[0]),
        大域メートル::生成する(成分[1]),
        大域メートル::生成する(成分[2]),
    )
}
