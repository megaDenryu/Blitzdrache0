//! 進行段階が1刻みでどう移るかの工程を所有する。触れるのは`ゲームの進行段階`自身と操作の意図だけであり、
//! プレイヤーの位置と場所巡りの進行には触れない。
//!
//! 決定とキャンセルが同じフレームに届いたときはキャンセルを先に効かせる。終了確認で両方を受けて終了してしまうと、
//! 取り消したはずの操作でゲームが閉じるためである。

use crate::game_intent::ゲームインテント;
use crate::progress_stage::{ゲームの進行段階, 終了確認から戻る段階};

impl ゲームの進行段階 {
    /// 今の段階と操作の意図から、次のフレームの進行段階を決める。
    pub(crate) fn 次の段階を決める(self, インテント: ゲームインテント) -> Self {
        match self {
            Self::タイトル表示中 => タイトル表示中から移る(インテント),
            Self::場所巡り中 => 場所巡り中から移る(インテント),
            Self::終了確認中 {
                取り消したときに戻る段階
            } => 終了確認中から移る(取り消したときに戻る段階, インテント),
            // 終了が決まった後はどの操作も受け付けない。閉じる途中のフレームでプレイへ戻ると、終了の判定が2度目を待つことになる。
            Self::終了決定済み => Self::終了決定済み,
        }
    }
}

fn タイトル表示中から移る(インテント: ゲームインテント) -> ゲームの進行段階 {
    if インテント.キャンセルを押したか {
        return ゲームの進行段階::終了確認中 {
            取り消したときに戻る段階: 終了確認から戻る段階::タイトル表示中,
        };
    }
    if インテント.決定を押したか {
        return ゲームの進行段階::場所巡り中;
    }
    ゲームの進行段階::タイトル表示中
}

fn 場所巡り中から移る(インテント: ゲームインテント) -> ゲームの進行段階 {
    if インテント.キャンセルを押したか {
        return ゲームの進行段階::終了確認中 {
            取り消したときに戻る段階: 終了確認から戻る段階::場所巡り中,
        };
    }
    ゲームの進行段階::場所巡り中
}

fn 終了確認中から移る(
    取り消したときに戻る段階: 終了確認から戻る段階, インテント: ゲームインテント
) -> ゲームの進行段階 {
    if インテント.キャンセルを押したか {
        return 取り消したときに戻る段階.進行段階へ写す();
    }
    if インテント.決定を押したか {
        return ゲームの進行段階::終了決定済み;
    }
    ゲームの進行段階::終了確認中 {
        取り消したときに戻る段階
    }
}
