//! カメラの遮蔽と復帰の検査が共有する構図。注視点を東0メートル・天頂1メートル・南0メートルに置き、理想視点を真南へ
//! 理想距離だけ離した位置に置く。壁を南4メートルに置くと、半径0.25メートルの球は南3.75メートルで触れるため、
//! 理想距離8メートルなら動けた割合は0.46875である。

use blitz_design::問い合わせを伴う状態遷移成功結果;
use blitz_math::{メートル, 大域メートル, 大域ワールド位置, 秒};

use crate::前の描画::前の描画の表示距離;
use crate::検査用の世界::平面と段と壁の世界;
use crate::表示距離::表示距離の決定;
use crate::遮蔽と復帰::カメラの遮蔽と復帰;
use crate::遮蔽の入力::遮蔽の判定の入力;
use crate::遮蔽の判定の選択肢::遮蔽の判定;

pub(crate) const 基本刻みの秒: f32 = 1.0 / 60.0;

fn 注視点() -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(1.0), 大域メートル::生成する(0.0))
}

fn 真南の理想視点(理想距離: f32) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(1.0), 大域メートル::生成する(f64::from(理想距離)))
}

/// 検査が1描画ぶん与える、状態遷移の状態(前の描画の表示距離)と状態遷移パラメータ(遮蔽の判定の入力)の組。
pub(crate) struct 検査の描画 {
    前の表示距離: 前の描画の表示距離,
    入力: 遮蔽の判定の入力,
}

pub(crate) fn 判定の入力(理想距離: f32, 前の表示距離: 前の描画の表示距離) -> 検査の描画 {
    検査の描画 {
        前の表示距離,
        入力: 遮蔽の判定の入力::生成する(注視点(), 真南の理想視点(理想距離), メートル::生成する(理想距離), メートル::生成する(0.5), 秒::生成する(基本刻みの秒)),
    }
}

pub(crate) fn 描いた前の描画(表示距離: f32, 理想距離: f32) -> 前の描画の表示距離 {
    前の描画の表示距離::描いた {
        表示距離: メートル::生成する(表示距離),
        理想距離: メートル::生成する(理想距離),
    }
}

pub(crate) fn 壁の無い世界() -> 平面と段と壁の世界 {
    平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0))
}

pub(crate) fn 南4メートルに壁のある世界() -> 平面と段と壁の世界 {
    壁の無い世界().壁を置く(大域メートル::生成する(4.0))
}

pub(crate) fn 表示距離と判定を決める(世界: &mut 平面と段と壁の世界, 描画: 検査の描画) -> (メートル, 遮蔽の判定) {
    let 成功 = 次の描画の表示距離へ進める(世界, 描画);
    (成功.観測.表示距離(), 成功.観測.判定())
}

pub(crate) fn 次の描画の表示距離へ進める(世界: &mut 平面と段と壁の世界, 描画: 検査の描画) -> 問い合わせを伴う状態遷移成功結果<前の描画の表示距離, 表示距離の決定> {
    match 描画.前の表示距離.遮蔽を判定して次の描画の表示距離へ進める(&カメラの遮蔽と復帰::初版の値で生成する(), 描画.入力, 世界) {
        Ok(成功) => 成功,
        Err(失敗) => match 失敗.失敗の理由 {},
    }
}
