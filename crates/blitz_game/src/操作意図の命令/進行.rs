//! 進行の操作。ゲームの進行段階の遷移が読む命令と、確定済みの操作入力からの解釈を所有する。
//!
//! 取り消しと決定が同じ刻みに届いたときは取り消すへ解釈する。終了確認で両方を受けて終了してしまうと、
//! 取り消したはずの操作でゲームが閉じるためである。参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断6」。

use blitz_design::{Mコマンド, M不変データ, M解釈関数};

use crate::confirmed_input::確定済みの操作入力;

/// 進行段階を動かす命令。取り消すは終了確認を開くか閉じ、決定するは始めるか終了を決める。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 進行の操作 {
    取り消す,
    決定する,
    何もしない,
}

impl M不変データ for 進行の操作 {}
impl Mコマンド for 進行の操作 {}

impl 進行の操作 {
    /// 取り消しと決定を押した瞬間から進行の操作を導く。両方を押した刻みは取り消すである。
    pub fn 確定済みの操作入力から解釈する(入力: &確定済みの操作入力) -> Self {
        let 押した瞬間の操作 = 入力.押した瞬間の操作();
        match (押した瞬間の操作.取り消し操作を押した瞬間か(), 押した瞬間の操作.決定操作を押した瞬間か()) {
            (true, _) => Self::取り消す,
            (false, true) => Self::決定する,
            (false, false) => Self::何もしない,
        }
    }
}

// 確定済みの操作入力から解釈する が解釈の役割(M解釈前の入力 から Mコマンド)を満たすことをコンパイラに確かめさせる。
const _: M解釈関数<確定済みの操作入力, 進行の操作> = M解釈関数::生成する(進行の操作::確定済みの操作入力から解釈する);
