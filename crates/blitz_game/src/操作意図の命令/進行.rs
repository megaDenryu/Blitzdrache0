//! 進行の操作。ゲームの進行段階の状態遷移が読む命令と、確定済みの操作入力からの解釈を所有する。
//!
//! キャンセルと決定が同じ刻みに届いたときはキャンセルするへ解釈する。終了確認で両方を受けて終了してしまうと、
//! キャンセルしたはずの操作でゲームが閉じるためである。参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断6」。

use blitz_design::{Mコマンド, M不変データ, M状態遷移が受け取る命令, M解釈関数};

use crate::確定済みの入力::確定済みの操作入力;

/// 進行段階を動かす命令。キャンセルするは終了確認を開くか閉じ、決定するは始めるか終了を決める。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 進行の操作 {
    キャンセルする,
    決定する,
    何もしない,
}

impl M不変データ for 進行の操作 {}
impl Mコマンド for 進行の操作 {}
impl M状態遷移が受け取る命令 for 進行の操作 {}

impl 進行の操作 {
    /// キャンセルと決定を押した瞬間から進行の操作を導く。両方を押した刻みはキャンセルするである。
    pub fn 確定済みの操作入力から変換する(入力: &確定済みの操作入力) -> Self {
        let 押した瞬間の操作 = 入力.押した瞬間の操作();
        match (押した瞬間の操作.キャンセル操作を押した瞬間か(), 押した瞬間の操作.決定操作を押した瞬間か()) {
            (true, _) => Self::キャンセルする,
            (false, true) => Self::決定する,
            (false, false) => Self::何もしない,
        }
    }
}

// 確定済みの操作入力から変換する が解釈の役割(M解釈前の入力 から Mコマンド)を満たすことをコンパイラに確かめさせる。
const _: M解釈関数<確定済みの操作入力, 進行の操作> = M解釈関数::生成する(進行の操作::確定済みの操作入力から変換する);
