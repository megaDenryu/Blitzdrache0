//! 胴体の移動の命令の組。胴体の移動の状態遷移が1刻みにコマンドの位置で受け取る、同じ刻みに届いた2つの命令(水平移動の操作とジャンプの操作)の全体を所有する。
//!
//! 2つの命令を1つの列挙の選択肢へ掛け合わせず(ジャンプせずに動く・ジャンプして動く)、命令ごとの `Mコマンド` をフィールドに並べた `M命令の組` にするのは、
//! 2026-09-28 のオーナー裁定による。水平の動きとジャンプするかは独立な2つの選択であり、選択肢へ展開すると、選択が増えるたびに選択肢が掛け算で増え、
//! 各命令を確定済みの操作入力から導く解釈を `M解釈関数` と宣言できなくなるためである。
//! 組は解釈しない。各命令の解釈が済んだ値を並べるだけであり、確定済みの操作入力から組むときも命令ごとの解釈を呼ぶ。

use blitz_design::{M不変データ, M命令の組, M状態遷移が受け取る命令};

use super::ジャンプ::ジャンプの操作;
use super::水平移動::水平移動の操作;
use crate::確定済みの入力::確定済みの操作入力;

/// 胴体を1刻みにどう動かすかの、同じ刻みに届いた命令の全体。水平にどう動くかと、ジャンプするかを持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 胴体の移動の命令の組 {
    水平移動の操作: 水平移動の操作,
    ジャンプの操作: ジャンプの操作,
}

impl M不変データ for 胴体の移動の命令の組 {}
impl M状態遷移が受け取る命令 for 胴体の移動の命令の組 {}
impl M命令の組 for 胴体の移動の命令の組 {}

impl 胴体の移動の命令の組 {
    pub fn 生成する(水平移動の操作: 水平移動の操作, ジャンプの操作: ジャンプの操作) -> Self {
        Self { 水平移動の操作, ジャンプの操作 }
    }

    /// 何も操作しなかった刻みの命令の組。止まったままジャンプしない。
    pub fn 何もしない() -> Self {
        Self::生成する(水平移動の操作::止まる, ジャンプの操作::ジャンプしない)
    }

    /// 確定済みの操作入力を、命令ごとの解釈で読み替えて組にする。
    pub fn 確定済みの操作入力から組む(入力: &確定済みの操作入力) -> Self {
        Self::生成する(水平移動の操作::確定済みの操作入力から変換する(入力), ジャンプの操作::確定済みの操作入力から変換する(入力))
    }

    pub fn 水平移動の操作(&self) -> 水平移動の操作 {
        self.水平移動の操作
    }

    pub fn ジャンプの操作(&self) -> ジャンプの操作 {
        self.ジャンプの操作
    }
}
