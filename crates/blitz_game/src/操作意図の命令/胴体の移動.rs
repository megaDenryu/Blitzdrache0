//! 胴体の移動の操作。胴体の移動の遷移が1刻みに読む、水平にどう動くかとジャンプするかを1つにした命令と、確定済みの操作入力からの解釈を所有する。
//!
//! 命令をそれを読む処理ごとに分けるのは、2026-09-27 のオーナー裁定の案1による。水平の動きとジャンプをこの1つの命令へまとめたのは実装員の判断であり、オーナーの確認待ちである。
//! まとめたのは、胴体の移動の遷移がコマンドの型引数を1つだけ受けるためである。
//! 水平の動きとジャンプを2つの命令に分けると、1つの遷移が2つのコマンドを受けることになり、関数の役割のコマンドの位置へ入れられない。
//! ジャンプするかを選択肢で分け、水平の動きを両方の選択肢に持たせるのは、ジャンプする刻みにも水平の動きがあり(初速に水平の速度が乗る)、
//! 2つの独立な選択の組を1つの判別型として表すためである。
//! ジャンプするは押した瞬間の操作であり、接地中の刻みにだけ意味を持つ。

use blitz_design::{Mコマンド, M不変データ, M解釈関数};

use super::水平移動::水平移動の操作;
use crate::確定済みの入力::確定済みの操作入力;

/// 胴体を1刻みにどう動かすかの命令。水平の動きを持ち、ジャンプするかを選択肢で分ける。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 胴体の移動の操作 {
    ジャンプせずに動く(水平移動の操作),
    ジャンプして動く(水平移動の操作),
}

impl M不変データ for 胴体の移動の操作 {}
impl Mコマンド for 胴体の移動の操作 {}

impl 胴体の移動の操作 {
    /// 何も操作しなかった刻みの命令。止まったままジャンプしない。
    pub fn 何もしない() -> Self {
        Self::ジャンプせずに動く(水平移動の操作::止まる)
    }

    /// 水平の動きを移動の4つの押下と走る操作から解釈し、ジャンプを押した瞬間ならジャンプして動く、そうでなければジャンプせずに動くとする。
    pub fn 確定済みの操作入力から解釈する(入力: &確定済みの操作入力) -> Self {
        let 水平移動 = 水平移動の操作::確定済みの操作入力から読み取る(入力);
        if 入力.押した瞬間の操作().ジャンプ操作を押した瞬間か() {
            Self::ジャンプして動く(水平移動)
        } else {
            Self::ジャンプせずに動く(水平移動)
        }
    }

    /// 水平にどう動くか。
    pub fn 水平移動の操作(&self) -> 水平移動の操作 {
        match self {
            Self::ジャンプせずに動く(水平移動) | Self::ジャンプして動く(水平移動) => *水平移動,
        }
    }

    /// ジャンプするか。
    pub fn ジャンプするか(&self) -> bool {
        match self {
            Self::ジャンプして動く(_) => true,
            Self::ジャンプせずに動く(_) => false,
        }
    }
}

