//! 水平移動の操作。胴体の移動の状態遷移が命令の組(`胴体の移動の命令の組`)を通して読む、止まる・歩く・走るの命令と、確定済みの操作入力からの解釈を所有する。
//!
//! 解釈の関数(`確定済みの操作入力から変換する`)は、倒していないときに走るを作らない。倒していない刻みに走る操作を押しても速さを掛ける向きが無く、止まると同じ動きになるためである。
//! 型はこれを保証しない。`水平移動の操作::走る(前後左右の操作量::中立())` も作れる。
//! 前後と左右の両方を同時に押した軸は打ち消し合って中立になり、前後と左右とも中立なら止まるである。

use blitz_design::{Mコマンド, M不変データ, M状態遷移が受け取る命令, M解釈関数};

use super::前後左右::前後左右の操作量;
use crate::操作軸::操作軸の倒し量;
use crate::確定済みの入力::確定済みの操作入力;

/// 胴体を水平にどう動かすかの命令。歩くと走るは前後左右の操作量を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 水平移動の操作 {
    止まる,
    歩く(前後左右の操作量),
    走る(前後左右の操作量),
}

impl M不変データ for 水平移動の操作 {}
impl M状態遷移が受け取る命令 for 水平移動の操作 {}
impl Mコマンド for 水平移動の操作 {}

impl 水平移動の操作 {
    /// 移動の4つの押下から前後左右の操作量を組み、前後と左右とも中立なら止まる、倒していて走る操作を押していれば走る、押していなければ歩くとする。
    pub fn 確定済みの操作入力から変換する(入力: &確定済みの操作入力) -> Self {
        let 押下が続く操作 = 入力.押下が続く操作();
        let 倒し量 = 前後左右の操作量::生成する(
            操作軸の倒し量::押下の対から生成する(押下が続く操作.前へ進む操作を押しているか(), 押下が続く操作.後ろへ下がる操作を押しているか()),
            操作軸の倒し量::押下の対から生成する(押下が続く操作.右へ寄る操作を押しているか(), 押下が続く操作.左へ寄る操作を押しているか()),
        );
        match (倒し量.中立か(), 押下が続く操作.走る操作を押しているか()) {
            (true, _) => Self::止まる,
            (false, true) => Self::走る(倒し量),
            (false, false) => Self::歩く(倒し量),
        }
    }

    /// 倒している前後左右の操作量。止まるなら前後と左右とも中立である。
    pub fn 前後左右の操作量(&self) -> 前後左右の操作量 {
        match self {
            Self::止まる => 前後左右の操作量::中立(),
            Self::歩く(倒し量) | Self::走る(倒し量) => *倒し量,
        }
    }

    /// 走るか。接地中の速さを歩く速さから走る速さへ変える。
    pub fn 走るか(&self) -> bool {
        match self {
            Self::走る(_) => true,
            Self::止まる | Self::歩く(_) => false,
        }
    }
}

// 確定済みの操作入力から変換する が解釈の役割(M解釈前の入力 から Mコマンド)を満たすことをコンパイラに確かめさせる。
const _: M解釈関数<確定済みの操作入力, 水平移動の操作> = M解釈関数::生成する(水平移動の操作::確定済みの操作入力から変換する);
