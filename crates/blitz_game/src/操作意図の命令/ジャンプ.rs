//! ジャンプの操作。胴体の移動が読む、ジャンプするかしないかの命令と、確定済みの操作入力からの解釈を所有する。
//! ジャンプするは押した瞬間の操作であり、接地中の刻みにだけ意味を持つ。

use blitz_design::{Mコマンド, M不変データ, M解釈関数};

use crate::確定済みの入力::確定済みの操作入力;

/// 胴体をジャンプさせるかの命令。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ジャンプの操作 {
    ジャンプする,
    ジャンプしない,
}

impl M不変データ for ジャンプの操作 {}
impl Mコマンド for ジャンプの操作 {}

impl ジャンプの操作 {
    /// ジャンプを押した瞬間ならジャンプする、そうでなければジャンプしないである。
    pub fn 確定済みの操作入力から解釈する(入力: &確定済みの操作入力) -> Self {
        if 入力.押した瞬間の操作().ジャンプ操作を押した瞬間か() {
            Self::ジャンプする
        } else {
            Self::ジャンプしない
        }
    }
}

// 確定済みの操作入力から解釈する が解釈の役割(M解釈前の入力 から Mコマンド)を満たすことをコンパイラに確かめさせる。
const _: M解釈関数<確定済みの操作入力, ジャンプの操作> = M解釈関数::生成する(ジャンプの操作::確定済みの操作入力から解釈する);
