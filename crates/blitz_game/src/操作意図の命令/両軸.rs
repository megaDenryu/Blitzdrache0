//! 両軸の倒し量。移動の操作の前後と左右の2軸の倒し量を組にした値を所有する。水平移動の操作の歩く・走るが持つ。

use blitz_design::{M不変データ, M値オブジェクト};

use crate::operation_axis::操作軸の倒し量;

/// 前後と左右の2軸の倒し量の組。前後は正が前(北へ向かう向き)、左右は正が右(東へ向かう向き)である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 両軸の倒し量 {
    前後の倒し量: 操作軸の倒し量,
    左右の倒し量: 操作軸の倒し量,
}

impl M不変データ for 両軸の倒し量 {}
impl M値オブジェクト for 両軸の倒し量 {}

impl 両軸の倒し量 {
    pub fn 生成する(前後の倒し量: 操作軸の倒し量, 左右の倒し量: 操作軸の倒し量) -> Self {
        Self { 前後の倒し量, 左右の倒し量 }
    }

    /// どちらの軸も倒していない組。
    pub fn 中立() -> Self {
        Self::生成する(操作軸の倒し量::中立(), 操作軸の倒し量::中立())
    }

    pub fn 前後の倒し量(&self) -> 操作軸の倒し量 {
        self.前後の倒し量
    }

    pub fn 左右の倒し量(&self) -> 操作軸の倒し量 {
        self.左右の倒し量
    }

    /// どちらの軸も倒していないか。
    pub fn 中立か(&self) -> bool {
        *self == Self::中立()
    }
}
