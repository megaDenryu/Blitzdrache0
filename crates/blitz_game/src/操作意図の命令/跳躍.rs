//! 跳躍の操作。胴体の移動が読む、跳ぶか跳ばないかの命令と、確定済みの操作入力からの解釈を所有する。
//! 跳ぶは押した瞬間の操作であり、接地中の刻みにだけ意味を持つ。

use blitz_design::{Mコマンド, M不変データ, M解釈関数};

use crate::confirmed_input::確定済みの操作入力;

/// 胴体を跳ばせるかの命令。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 跳躍の操作 {
    跳ぶ,
    跳ばない,
}

impl M不変データ for 跳躍の操作 {}
impl Mコマンド for 跳躍の操作 {}

impl 跳躍の操作 {
    /// ジャンプを押した瞬間なら跳ぶ、そうでなければ跳ばないである。
    pub fn 確定済みの操作入力から解釈する(入力: &確定済みの操作入力) -> Self {
        if 入力.押した瞬間の操作().ジャンプ操作を押した瞬間か() { Self::跳ぶ } else { Self::跳ばない }
    }
}

// 確定済みの操作入力から解釈する が解釈の役割(M解釈前の入力 から Mコマンド)を満たすことをコンパイラに確かめさせる。
const _: M解釈関数<確定済みの操作入力, 跳躍の操作> = M解釈関数::生成する(跳躍の操作::確定済みの操作入力から解釈する);
