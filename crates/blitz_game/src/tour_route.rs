//! 巡る目的地の並び(道順)と、その並びの中の位置を指す番号を所有する。道順は実行中に変わらない値であり、
//! どこまで巡ったかは場所巡りの進行が別に持つ。2つを別の型にするのは、毎フレーム持ち回るのが番号だけで済むためである。

use crate::destination::目的地;

/// 道順の中で何番目の目的地かを表す番号。0が最初の目的地である。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 目的地番号(usize);

impl 目的地番号 {
    /// 最初に向かう目的地の番号。
    pub fn 最初() -> Self {
        Self(0)
    }

    pub fn 次の番号(self) -> Self {
        Self(self.0 + 1)
    }

    /// 目的地の列の添字として使うための取り出し。
    pub fn 添字(self) -> usize {
        self.0
    }
}

/// 巡る目的地を順に並べた道順。
#[derive(Debug, Clone, PartialEq)]
pub struct 場所巡りの道順 {
    目的地の列: Vec<目的地>,
}

impl 場所巡りの道順 {
    /// 注意: 目的地の列は非空でなければならない。空の道順は最初から全踏破であり、巡るという遊びが成立しない。
    /// 到達したらバグである状態のためpanicで止める。
    pub fn 生成する(目的地の列: Vec<目的地>) -> Self {
        assert!(!目的地の列.is_empty(), "場所巡りの道順の目的地の列は非空でなければならない");
        Self { 目的地の列 }
    }

    pub fn 目的地の総数(&self) -> usize {
        self.目的地の列.len()
    }

    /// 巡る順に並んだ目的地の全件。目印を据える位置と、目的地の天頂成分を地表へ置き直す工程がこれを読む。
    pub fn 目的地一覧(&self) -> &[目的地] {
        &self.目的地の列
    }

    /// 番号の指す目的地を返す。全ての目的地へ到達した後の番号は列の外側を指すため、`None`が返る。
    pub fn 番号の目的地を参照する(&self, 番号: 目的地番号) -> Option<目的地> {
        self.目的地の列.get(番号.添字()).copied()
    }
}
