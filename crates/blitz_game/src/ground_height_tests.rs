//! 足元の地面の高さの反映の検査。高さが分かった枝だけが天頂成分を動かし、水平の2成分は動かないことを見る。

use blitz_math::{大域メートル, 大域ワールド位置};

use crate::game_state::場所巡りのゲームの状態;
use crate::ground_height::足元の地面の高さ;

fn 東三南五の出発地点() -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(3.0), 大域メートル::生成する(0.0), 大域メートル::生成する(5.0))
}

#[test]
fn 高さ場から参照した高さは天頂成分だけを動かす() {
    let 状態 = 場所巡りのゲームの状態::開始時の状態を作る(東三南五の出発地点());
    let 反映後 = 状態.足元の地面の高さを反映した状態を返す(足元の地面の高さ::高さ場から参照した高さ(大域メートル::生成する(12.5)));
    let 位置 = 反映後.プレイヤーの大域位置();
    assert_eq!(位置.x(), 大域メートル::生成する(3.0));
    assert_eq!(位置.y(), 大域メートル::生成する(12.5));
    assert_eq!(位置.z(), 大域メートル::生成する(5.0));
}

/// 反証: 高さが分からない枝で天頂成分を0へ落とすと、標高0の平地と区別が付かなくなる。
#[test]
fn 高さが分からない枝は位置を1つも動かさない() {
    let 状態 = 場所巡りのゲームの状態::開始時の状態を作る(東三南五の出発地点())
        .足元の地面の高さを反映した状態を返す(足元の地面の高さ::高さ場から参照した高さ(大域メートル::生成する(9.0)));
    for 分からない枝 in [足元の地面の高さ::高さ場を持たない世界, 足元の地面の高さ::高さ場の広がりの外] {
        let 反映後 = 状態.足元の地面の高さを反映した状態を返す(分からない枝);
        assert_eq!(反映後.プレイヤーの大域位置(), 状態.プレイヤーの大域位置());
    }
}
