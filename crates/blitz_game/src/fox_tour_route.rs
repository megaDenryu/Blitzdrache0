//! クソゲー1本目「キツネの場所巡り」が巡る目的地の表を所有する。巡る先の数・水平の位置・到達とみなす半径をここだけが決める。
//!
//! 世界の宣言をゲーム側の表へ移す最初の1枚である。検収のための世界の分岐はblitz_appへ残す。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断4」。
//!
//! 天頂成分を0で作るのは、目的地の高さがその場所の地表高さで決まり、地表高さがエンジンの語彙だからである。
//! コンポジションルートが世界の高さ場を据えるときに`天頂成分を据えた目的地を返す`で置き直す。
//!
//! 注意: 水平の位置は、目印の柱を据えるアセットコンパイラの宣言
//! (`crates/blitz_asset_compiler/src/runtime_compilation/world/fox_tour_declaration.rs`)と同じ数でなければならない。
//! 食い違うと、柱が立っていない場所で到達が成立するか、柱の足元で到達が成立しないかのどちらかになる。

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};

use crate::destination::目的地;
use crate::tour_route::場所巡りの道順;

/// 目的地に立ったとみなす距離。目印の柱の一辺0.8メートルより広く取り、柱に触れる手前で到達が成立するようにする。
const 到達とみなす半径メートル: f32 = 3.0;

/// クソゲー1本目の道順。1つ目は出発地点の真北にあり、2つ目と3つ目は向きを変えないと着かない位置に置く。
pub fn キツネの場所巡りの道順を作る() -> 場所巡りの道順 {
    場所巡りの道順::生成する(vec![
        東と南のメートルから目的地を作る(0.0, -15.0),
        東と南のメートルから目的地を作る(-40.0, -45.0),
        東と南のメートルから目的地を作る(45.0, -70.0),
    ])
}

/// ワールド軸の水平2成分から目的地を1つ作る。半径はこの表の全ての目的地で同じである。
fn 東と南のメートルから目的地を作る(東: f64, 南: f64) -> 目的地 {
    目的地::生成する(
        大域ワールド位置::生成する(大域メートル::生成する(東), 大域メートル::生成する(0.0), 大域メートル::生成する(南)),
        メートル::生成する(到達とみなす半径メートル),
    )
}
