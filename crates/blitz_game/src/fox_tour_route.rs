//! クソゲー1本目「キツネの場所巡り」が巡る目的地の表を所有する。巡る先の数・位置・到達とみなす半径をここだけが決める。
//!
//! 世界の宣言をゲーム側の表へ移す最初の1枚である。検収のための世界の分岐はblitz_appへ残す。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断4」。

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};

use crate::destination::目的地;
use crate::tour_route::場所巡りの道順;

/// 目的地に立ったとみなす距離。目印のメッシュの見た目より広く取り、真上を通らなくても到達が成立するようにする。
const 到達とみなす半径メートル: f32 = 3.0;

/// クソゲー1本目の道順。出発地点の北側へ3つの目的地を置き、順に巡る。
pub fn キツネの場所巡りの道順を作る() -> 場所巡りの道順 {
    場所巡りの道順::生成する(vec![
        東と天頂と南のメートルから目的地を作る(20.0, 0.0, -20.0),
        東と天頂と南のメートルから目的地を作る(-25.0, 0.0, -40.0),
        東と天頂と南のメートルから目的地を作る(0.0, 0.0, -60.0),
    ])
}

/// ワールド軸の3成分から目的地を1つ作る。半径はこの表の全ての目的地で同じである。
fn 東と天頂と南のメートルから目的地を作る(東: f64, 天頂: f64, 南: f64) -> 目的地 {
    目的地::生成する(
        大域ワールド位置::生成する(大域メートル::生成する(東), 大域メートル::生成する(天頂), 大域メートル::生成する(南)),
        メートル::生成する(到達とみなす半径メートル),
    )
}
