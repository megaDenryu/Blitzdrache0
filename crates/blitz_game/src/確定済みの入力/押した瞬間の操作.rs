//! 確定済みの操作入力のうち、押した瞬間だけ意味を持つ4つの操作(決定・キャンセル・ジャンプ・カメラの系統の切替)。

use blitz_design::{M不変データ, M中間入力, M解釈前の入力};

/// 押した瞬間だけ意味を持つ操作を、それぞれ押した瞬間かで持つ値。
///
/// 押しているかでなく押した瞬間かで持つのは、押しっぱなしの間ずっと決定が届くとメニューが1フレームで流れ、
/// ジャンプが届き続けると着地のたびにジャンプし直し、切替が届き続けると系統が描画ごとに入れ替わるためである。
/// 同じ真偽の4つを位置の引数で受ける生成の口を置かず、`無操作` から操作ごとの口で1つずつ置き換えるのは、取り違えても型が通るためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 押した瞬間の操作の入力 {
    決定操作を押した瞬間か: bool,
    キャンセル操作を押した瞬間か: bool,
    ジャンプ操作を押した瞬間か: bool,
    カメラの系統を切り替える操作を押した瞬間か: bool,
}

impl M不変データ for 押した瞬間の操作の入力 {}
impl M解釈前の入力 for 押した瞬間の操作の入力 {}
impl M中間入力 for 押した瞬間の操作の入力 {}

impl 押した瞬間の操作の入力 {
    /// どの操作も押されていない値。
    pub fn 無操作() -> Self {
        Self::default()
    }

    pub fn 決定操作を押した瞬間かを置き換えた入力(self, 決定操作を押した瞬間か: bool) -> Self {
        Self { 決定操作を押した瞬間か, ..self }
    }

    pub fn キャンセル操作を押した瞬間かを置き換えた入力(self, キャンセル操作を押した瞬間か: bool) -> Self {
        Self {
            キャンセル操作を押した瞬間か, ..self
        }
    }

    pub fn ジャンプ操作を押した瞬間かを置き換えた入力(self, ジャンプ操作を押した瞬間か: bool) -> Self {
        Self {
            ジャンプ操作を押した瞬間か, ..self
        }
    }

    pub fn カメラの系統を切り替える操作を押した瞬間かを置き換えた入力(self, カメラの系統を切り替える操作を押した瞬間か: bool) -> Self {
        Self {
            カメラの系統を切り替える操作を押した瞬間か,
            ..self
        }
    }

    pub fn 決定操作を押した瞬間か(&self) -> bool {
        self.決定操作を押した瞬間か
    }

    pub fn キャンセル操作を押した瞬間か(&self) -> bool {
        self.キャンセル操作を押した瞬間か
    }

    pub fn ジャンプ操作を押した瞬間か(&self) -> bool {
        self.ジャンプ操作を押した瞬間か
    }

    pub fn カメラの系統を切り替える操作を押した瞬間か(&self) -> bool {
        self.カメラの系統を切り替える操作を押した瞬間か
    }
}
