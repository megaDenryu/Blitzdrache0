//! 確定済みの操作入力のうち、押下が続く間ずっと意味を持つ5つの操作(前へ進む・後ろへ下がる・左へ寄る・右へ寄る・走る)。

use blitz_design::{M不変データ, M中間入力, M解釈前の入力};

/// 押下が続く操作を、それぞれ押しているかで持つ値。
/// 同じ真偽の5つを位置の引数で受ける生成の口を置かず、`無操作` から操作ごとの口で1つずつ置き換えるのは、取り違えても型が通るためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 押下が続く操作の入力 {
    前へ進む操作を押しているか: bool,
    後ろへ下がる操作を押しているか: bool,
    左へ寄る操作を押しているか: bool,
    右へ寄る操作を押しているか: bool,
    走る操作を押しているか: bool,
}

impl M不変データ for 押下が続く操作の入力 {}
impl M解釈前の入力 for 押下が続く操作の入力 {}
impl M中間入力 for 押下が続く操作の入力 {}

impl 押下が続く操作の入力 {
    /// どの操作も押されていない値。
    pub fn 無操作() -> Self {
        Self::default()
    }

    pub fn 前へ進む操作を押しているかを置き換えた入力(self, 前へ進む操作を押しているか: bool) -> Self {
        Self {
            前へ進む操作を押しているか, ..self
        }
    }

    pub fn 後ろへ下がる操作を押しているかを置き換えた入力(self, 後ろへ下がる操作を押しているか: bool) -> Self {
        Self {
            後ろへ下がる操作を押しているか, ..self
        }
    }

    pub fn 左へ寄る操作を押しているかを置き換えた入力(self, 左へ寄る操作を押しているか: bool) -> Self {
        Self {
            左へ寄る操作を押しているか, ..self
        }
    }

    pub fn 右へ寄る操作を押しているかを置き換えた入力(self, 右へ寄る操作を押しているか: bool) -> Self {
        Self {
            右へ寄る操作を押しているか, ..self
        }
    }

    pub fn 走る操作を押しているかを置き換えた入力(self, 走る操作を押しているか: bool) -> Self {
        Self { 走る操作を押しているか, ..self }
    }

    pub fn 前へ進む操作を押しているか(&self) -> bool {
        self.前へ進む操作を押しているか
    }

    pub fn 後ろへ下がる操作を押しているか(&self) -> bool {
        self.後ろへ下がる操作を押しているか
    }

    pub fn 左へ寄る操作を押しているか(&self) -> bool {
        self.左へ寄る操作を押しているか
    }

    pub fn 右へ寄る操作を押しているか(&self) -> bool {
        self.右へ寄る操作を押しているか
    }

    pub fn 走る操作を押しているか(&self) -> bool {
        self.走る操作を押しているか
    }
}
