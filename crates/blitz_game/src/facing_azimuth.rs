//! 動く個体が世界のどちらを向いているかを表す角と、目標の向きへ回す工程を所有する。触れるのは角そのものだけであり、
//! その個体が何であるかも、向きが絵にどう出るかも知らない。
//!
//! 角の測り方は`前へ進む向きの方位角`と同じである。Y軸まわりの正の回転で、0が北(Zの負の向き)、増えると西(Xの負の向き)へ回る。
//! 同じ測り方でも別の型にするのは、片方が操作の基準の向き、もう片方が個体の姿勢であり、混ぜてはならない量だからである。

use blitz_math::{ラジアン, ラジアン毎秒, 秒};

/// 円周の全角。角を半周の幅へ折り返す計算がこの値だけを使う。
const 一周のラジアン: f32 = std::f32::consts::TAU;

/// 動く個体が向いている方位角。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 動く個体が向いている方位角(ラジアン);

impl 動く個体が向いている方位角 {
    pub fn 生成する(角: ラジアン) -> Self {
        Self(半周の幅へ折り返した角(角))
    }

    /// 北を向いた姿勢。向きの出どころを持たない検査が使う。
    pub fn 北を向く() -> Self {
        Self(ラジアン::生成する(0.0))
    }

    /// 境界向けの取り出し。世界での向きを読込時の姿勢からの回転へ写す配線が読む。
    pub fn ラジアンで表した角(self) -> ラジアン {
        self.0
    }

    /// 目標の向きへ、1刻みで回れる角を上限に最短の回り方で回した向きを返す。
    ///
    /// 上限を置くのは、目標へ一息で飛ばすと真後ろへの向き直りが1フレームで終わり、
    /// 向きが変わった過程が絵に出ないためである。
    pub(crate) fn 目標の向きへ一刻みぶん回した向きを返す(
        self, 目標の向き: Self, 回る速さ: ラジアン毎秒, 刻み: 秒
    ) -> Self {
        let 差 = 半周の幅へ折り返した角(目標の向き.0 - self.0);
        let 一刻みで回れる角 = (回る速さ * 刻み).値();
        let 回る角 = 差.値().clamp(-一刻みで回れる角, 一刻みで回れる角);
        Self::生成する(self.0 + ラジアン::生成する(回る角))
    }
}

/// 角を半周の幅(-180度から180度まで)へ折り返す。向きの差をこの幅で測ると最短の回り方が選べ、
/// 向きそのものをこの幅に保つと、同じ方向へ回り続けても角が際限なく増えて刻みが潰れることがない。
fn 半周の幅へ折り返した角(角: ラジアン) -> ラジアン {
    let 折り返した = 角.値().rem_euclid(一周のラジアン);
    if 折り返した > 一周のラジアン / 2.0 {
        return ラジアン::生成する(折り返した - 一周のラジアン);
    }
    ラジアン::生成する(折り返した)
}
