use crate::進行段階::ゲームの進行段階;
use crate::道順::場所巡りの道順;

/// 場所を巡るゲームが1刻みごとに更新する状態一式。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 場所巡りのゲームの状態 {
    進行段階: ゲームの進行段階,
    場所巡り: 場所巡りの進行,
    プレイヤー: プレイヤーの状態,
}

impl M不変データ for 場所巡りのゲームの状態 {}
impl M状態 for 場所巡りのゲームの状態 {}

impl 場所巡りのゲームの状態 {
    /// 出発時の向きを外から受け取るのは、それがキツネの絵がどちらを向いて焼かれているかで決まる値であり、ゲームの規則ではないためである。
    pub fn 開始時の状態を作る(出発地点: 大域ワールド位置, 出発時の向き: 動く個体が向いている方位角) -> Self {
        Self {
            進行段階: ゲームの進行段階::タイトル表示中,
            場所巡り: 場所巡りの進行::出発前の進行を作る(),
            プレイヤー: プレイヤーの状態::開始時の状態を作る(出発地点, 出発時の向き),
        }
    }

    /// 操作の意図のうち進行の操作で進行段階を遷移させた状態を返す。触れるのは進行段階だけであり、プレイヤーと場所巡りの進行は動かさない。
    /// 固定刻みの工程の操作入力の適用と操作で決まる状態遷移の処理位置が呼ぶ(参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」)。
    pub fn 操作の意図で進行段階を遷移させた状態を返す(self, 進行の操作: &進行の操作) -> Self {
        Self {
            進行段階: self.進行段階.次の段階を決める(進行の操作),
            ..self
        }
    }

    /// プレイヤーを固定刻み1つぶん動かした状態と、その刻みの移動の観測を返す。進行段階を見ない。
    /// この刻みに動かすかどうかは、`ゲームの進行段階::移動と到達判定を行う段階か`を読んだ呼び出し側の決定である。
    /// 問い合わせが失敗したら、受け取った状態を口の失敗と一緒に返す。
    pub fn プレイヤーを胴体の移動の命令の組で動かした状態を返す<口: 世界の形を尋ねる口 + ?Sized>(
        self,
        操作: &胴体の移動の命令の組,
        規則: &胴体の移動,
        入力: 胴体の移動の遷移パラメータ,
        口: &mut 口,
    ) -> 問い合わせを伴う遷移の結果<Self, 移動の観測, 口::問い合わせエラー> {
        match self.プレイヤー.胴体の移動の命令の組で動かした状態を返す(操作, 規則, 入力, 口) {
            Ok(成功) => Ok(問い合わせを伴う遷移成功結果 {
                次の状態: Self { プレイヤー: 成功.次の状態, ..self },
                観測: 成功.観測,
            }),
            Err(失敗) => Err(遷移失敗結果 {
                元の状態: Self { プレイヤー: 失敗.元の状態, ..self },
                失敗の理由: 失敗.失敗の理由,
            }),
        }
    }

    /// 今のプレイヤーの大域位置で目的地への到達を判定し、場所巡りの進行を進めた状態を返す。進行段階を見ない。
    pub fn 目的地への到達を判定して場所巡りの進行を進めた状態を返す(self, 道順: &場所巡りの道順) -> Self {
        Self {
            場所巡り: self.場所巡り.到達を判定して進めた進行を返す(道順, 到達の判定の遷移パラメータ::生成する(self.プレイヤーの大域位置())),
            ..self
        }
    }

    /// 足元の地面の高さをプレイヤーの大域位置の天頂成分へ据えた状態を返す。高さ場を据える起動時の据え直しだけが使い、
    /// 毎刻みの接地は掃引による接地判定が決める。
    /// 据え直しはゲームの規則の遷移でなく、規則によらない書き換えである(参照: `_doc/設計/設計オントロジー.md` 第3節「規則によらない書き換え」)。
    ///
    /// 高さが分からない2つの選択肢で天頂成分を動かさないのは、0メートルへ落とすと標高0の平地と区別できず、
    /// 高さ場を焼き忘れた世界でキツネが地面へ沈んでも絵から理由が読み取れなくなるためである。
    pub fn 足元の地面の高さを反映した状態を返す(self, 地面の高さ: 足元の地面の高さ) -> Self {
        let 足元の地面の高さ::高さ場から参照した高さ(高さ) = 地面の高さ else {
            return self;
        };
        Self {
            プレイヤー: self.プレイヤー.天頂成分を据え直した状態を返す(高さ),
            ..self
        }
    }

    pub fn 進行段階(&self) -> ゲームの進行段階 {
        self.進行段階
    }

    pub fn 場所巡り(&self) -> 場所巡りの進行 {
        self.場所巡り
    }

    pub fn プレイヤーの大域位置(&self) -> 大域ワールド位置 {
        self.プレイヤー.位置と向き().大域位置()
    }

    pub fn プレイヤーの向き(&self) -> 動く個体が向いている方位角 {
        self.プレイヤー.位置と向き().向き()
    }

    pub fn プレイヤーの移動状態(&self) -> 移動状態 {
        self.プレイヤー.移動状態()
    }

    pub fn 終了が決まったか(&self) -> bool {
        self.進行段階 == ゲームの進行段階::終了決定済み
    }
}

// 描画・画面の表示・計器だけが読む3つの取り出しが、射影の役割(M状態 から M不変データ)を満たすことをコンパイラに確かめさせる。
// `進行段階`は、固定刻みの工程がこの刻みに移動と到達判定を行うかを決めるために読む(遷移の制御)ため、射影の役割を名乗らせない。
const _: M射影関数<場所巡りのゲームの状態, 動く個体が向いている方位角> = M射影関数::生成する(場所巡りのゲームの状態::プレイヤーの向き);
const _: M射影関数<場所巡りのゲームの状態, 場所巡りの進行> = M射影関数::生成する(場所巡りのゲームの状態::場所巡り);
const _: M射影関数<場所巡りのゲームの状態, 移動状態> = M射影関数::生成する(場所巡りのゲームの状態::プレイヤーの移動状態);

// 進行段階の遷移と、プレイヤーの移動と、到達判定が遷移の役割を満たすことをコンパイラに確かめさせる。移動の問い合わせ先と失敗は代表で具体化し、実際の失敗は口の実装が決める。
const _: M遷移が受け取る命令で決まる遷移関数<場所巡りのゲームの状態, 進行の操作> = M遷移が受け取る命令で決まる遷移関数::生成する(場所巡りのゲームの状態::操作の意図で進行段階を遷移させた状態を返す);
const _: M問い合わせを伴う遷移関数<場所巡りのゲームの状態, 胴体の移動の命令の組, 胴体の移動, 胴体の移動の遷移パラメータ, 口の実装を代表する口, 移動の観測, 口の実装が決める失敗の代表> =
    M問い合わせを伴う遷移関数::生成する(場所巡りのゲームの状態::プレイヤーを胴体の移動の命令の組で動かした状態を返す);
const _: M規則で決まる遷移関数<場所巡りのゲームの状態, 場所巡りの道順> = M規則で決まる遷移関数::生成する(場所巡りのゲームの状態::目的地への到達を判定して場所巡りの進行を進めた状態を返す);

// 足元の地面の高さを反映した状態を返す が、規則によらない書き換えの役割(状態を足元の地面の高さで外から書き換える)を満たすことをコンパイラに確かめさせる。
const _: M規則によらない書き換え関数<場所巡りのゲームの状態, 足元の地面の高さ> = M規則によらない書き換え関数::生成する(場所巡りのゲームの状態::足元の地面の高さを反映した状態を返す);
