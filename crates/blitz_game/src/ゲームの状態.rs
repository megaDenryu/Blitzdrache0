//! クソゲー1本目の状態一式と、規則の各処理位置の変換(進行段階の遷移・プレイヤーの移動・到達判定)を所有する。どの変換も今の状態を
//! 読んで新しい状態を返すだけであり、描画にもコンポジションルートにも触れない。世界の形を尋ねる口は刻みごとに借りて使う。
//!
//! 3つの変換をどの順で呼び、移動と到達判定をこの刻みに行うかは、固定刻みの工程(コンポジションルート)が
//! `ゲームの進行段階::移動と到達判定を行う段階か`を読んで決める。1刻みの長さもコンポジションルートが決めて渡す。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断1」「判断13」。

use blitz_design::{
    M不変データ, M問い合わせを伴う遷移関数, M射影関数, M状態, M規則で決まる遷移関数, M規則によらない書き換え関数, M遷移が受け取る命令で決まる遷移関数, 問い合わせを伴う遷移の結果, 問い合わせを伴う遷移成功結果, 遷移失敗結果
};
use blitz_math::大域ワールド位置;

use crate::プレイヤー::プレイヤーの状態;
use crate::世界の形::{世界の形を尋ねる口, 口の実装が決める失敗の代表, 口の実装を代表する口};
use crate::到達の判定::到達の判定の遷移パラメータ;
use crate::向いている方位角::動く個体が向いている方位角;
use crate::巡りの進行::場所巡りの進行;
use crate::操作意図の命令::{胴体の移動の命令の組, 進行の操作};
use crate::移動::移動の観測;
use crate::移動::移動状態;
