//! プレイヤーの足元の地面の高さが、そのフレームにどう決まったかの判別。
//!
//! 高さが分からない場合を枝で持ち、0メートルを返す枝を持たないのは、標高0の平地と「高さが分からない」が
//! 同じ値になると、地面へ沈んだのか平地に立っているのかを消費側が区別できなくなるためである。
//! この型をゲームロジック層が持つのは、高さの出どころ(高さ場アセット)がエンジンの語彙であり、
//! ゲームロジック層がその型を名指ししないためである。写しはコンポジションルートの配線が行う。

use blitz_math::大域メートル;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 足元の地面の高さ {
    高さ場を持たない世界, // プレイヤーの高さを1度も動かさない
    高さ場の広がりの外, // プレイヤーの水平位置が広がりの外。直前の高さを保つ
    高さ場から参照した高さ(大域メートル), // 高さ場から参照した地面の高さ
}
