//! 歩くだけのゲームが持つプレイヤーの状態。進行段階・目的地・道順を持たない。

use std::convert::Infallible;

use blitz_design::{M不変データ, M問い合わせを伴う遷移関数, M状態};
use blitz_math::大域ワールド位置;

use crate::プレイヤー::プレイヤーの状態;
use crate::世界の形::{世界の形を尋ねる口, 失敗しない代表の口};
use crate::移動::一刻みの移動の入力;
use crate::移動::移動の観測;
use crate::移動::移動状態;
use crate::移動::胴体の移動;
use crate::{プレイヤーの位置と向き, 動く個体が向いている方位角, 足元の地面の高さ};

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 歩くだけのゲームの状態 {
    プレイヤー: プレイヤーの状態,
}

impl M不変データ for 歩くだけのゲームの状態 {}
impl M状態 for 歩くだけのゲームの状態 {}

impl 歩くだけのゲームの状態 {
    pub fn 開始時の状態を作る(出発地点: 大域ワールド位置, 出発時の向き: 動く個体が向いている方位角) -> Self {
        Self {
            プレイヤー: プレイヤーの状態::開始時の状態を作る(出発地点, 出発時の向き),
        }
    }

    pub fn 一刻み進めた状態を返す<口: 世界の形を尋ねる口 + ?Sized>(self, 規則: &胴体の移動, 入力: 一刻みの移動の入力, 口: &mut 口) -> Result<(Self, 移動の観測), 口::問い合わせエラー> {
        let (プレイヤー, 観測) = self.プレイヤー.一刻み動かした状態を返す(規則, 入力, 口)?;
        Ok((Self { プレイヤー }, 観測))
    }

    /// 足元の地面の高さを天頂成分へ据えた状態。高さ場を据える起動時の据え直しだけが使い、毎刻みの接地は掃引による接地判定が決める。
    pub fn 足元の地面の高さを反映した状態を返す(self, 地面の高さ: 足元の地面の高さ) -> Self {
        let 足元の地面の高さ::高さ場から参照した高さ(高さ) = 地面の高さ else {
            return self;
        };
        Self {
            プレイヤー: self.プレイヤー.天頂成分を据え直した状態を返す(高さ),
        }
    }

    pub fn プレイヤーの位置と向き(self) -> プレイヤーの位置と向き {
        self.プレイヤー.位置と向き()
    }

    pub fn プレイヤーの移動状態(self) -> 移動状態 {
        self.プレイヤー.移動状態()
    }
}

// 一刻み進めた状態を返す が、問い合わせを伴う遷移の役割を満たすことをコンパイラに確かめさせる。問い合わせ先は代表の口で具体化する。
const _: M問い合わせを伴う遷移関数<歩くだけのゲームの状態, 胴体の移動, 一刻みの移動の入力, 失敗しない代表の口, 移動の観測, Infallible> = M問い合わせを伴う遷移関数::生成する(歩くだけのゲームの状態::一刻み進めた状態を返す);
