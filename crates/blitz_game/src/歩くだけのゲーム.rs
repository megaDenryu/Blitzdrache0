//! 歩くだけのゲームが持つプレイヤーの状態。進行段階・目的地・道順を持たない。

use blitz_design::{
    M不変データ, M問い合わせを伴う状態遷移関数, M状態, M規則によらない書き換え関数, 問い合わせを伴う状態遷移の結果, 問い合わせを伴う状態遷移成功結果, 状態遷移失敗結果
};
use blitz_math::大域ワールド位置;

use crate::プレイヤー::プレイヤーの状態;
use crate::世界の形::{世界の形を尋ねる口, 口の実装が決める失敗の代表, 口の実装を代表する口};
use crate::操作意図の命令::胴体の移動の命令の組;
use crate::移動::移動の観測;
use crate::移動::移動状態;
use crate::移動::胴体の移動;
use crate::移動::胴体の移動の状態遷移パラメータ;
use crate::{プレイヤーの位置と向き, 動く個体が向いている方位角, 足元の地面の高さ};

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 歩くだけのゲームの状態 {
    プレイヤー: プレイヤーの状態,
}

impl M不変データ for 歩くだけのゲームの状態 {}
impl M状態 for 歩くだけのゲームの状態 {}

impl 歩くだけのゲームの状態 {
    pub fn 開始時の状態を作る(出発地点: 大域ワールド位置, 出発時の向き: 動く個体が向いている方位角) -> Self {
        Self {
            プレイヤー: プレイヤーの状態::開始時の状態を作る(出発地点, 出発時の向き),
        }
    }

    /// 胴体の移動の命令の組でプレイヤーを1刻みぶん動かした状態と観測を返す。問い合わせが失敗したら、受け取った状態を口の失敗と一緒に返す。
    pub fn プレイヤーを胴体の移動の命令の組で動かした状態を返す<口: 世界の形を尋ねる口 + ?Sized>(
        self,
        操作: &胴体の移動の命令の組,
        規則: &胴体の移動,
        入力: 胴体の移動の状態遷移パラメータ,
        口: &mut 口,
    ) -> 問い合わせを伴う状態遷移の結果<Self, 移動の観測, 口::問い合わせエラー> {
        match self.プレイヤー.胴体の移動の命令の組で動かした状態を返す(操作, 規則, 入力, 口) {
            Ok(成功) => Ok(問い合わせを伴う状態遷移成功結果 {
                次の状態: Self { プレイヤー: 成功.次の状態 },
                観測: 成功.観測,
            }),
            Err(失敗) => Err(状態遷移失敗結果 {
                元の状態: Self { プレイヤー: 失敗.元の状態 },
                失敗の理由: 失敗.失敗の理由,
            }),
        }
    }

    /// 足元の地面の高さを天頂成分へ据えた状態。高さ場を据える起動時の据え直しだけが使い、毎刻みの接地は掃引による接地判定が決める。
    /// 据え直しはゲームの規則の状態遷移でなく、規則によらない書き換えである(参照: `_doc/設計/設計オントロジー.md` 第3節「規則によらない書き換え」)。
    pub fn 足元の地面の高さを反映した状態を返す(self, 地面の高さ: 足元の地面の高さ) -> Self {
        let 足元の地面の高さ::高さ場から参照した高さ(高さ) = 地面の高さ else {
            return self;
        };
        Self {
            プレイヤー: self.プレイヤー.天頂成分を据え直した状態を返す(高さ),
        }
    }

    pub fn プレイヤーの位置と向き(self) -> プレイヤーの位置と向き {
        self.プレイヤー.位置と向き()
    }

    pub fn プレイヤーの移動状態(self) -> 移動状態 {
        self.プレイヤー.移動状態()
    }
}

// プレイヤーを胴体の移動の命令の組で動かした状態を返す が、問い合わせを伴う状態遷移の役割を満たすことをコンパイラに確かめさせる。問い合わせ先と失敗は代表で具体化し、実際の失敗は口の実装が決める。
const _: M問い合わせを伴う状態遷移関数<歩くだけのゲームの状態, 胴体の移動の命令の組, 胴体の移動, 胴体の移動の状態遷移パラメータ, 口の実装を代表する口, 移動の観測, 口の実装が決める失敗の代表> =
    M問い合わせを伴う状態遷移関数::生成する(歩くだけのゲームの状態::プレイヤーを胴体の移動の命令の組で動かした状態を返す);

// 足元の地面の高さを反映した状態を返す が、規則によらない書き換えの役割(状態を足元の地面の高さで外から書き換える)を満たすことをコンパイラに確かめさせる。
const _: M規則によらない書き換え関数<歩くだけのゲームの状態, 足元の地面の高さ> = M規則によらない書き換え関数::生成する(歩くだけのゲームの状態::足元の地面の高さを反映した状態を返す);
