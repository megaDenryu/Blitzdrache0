//! 遮蔽の判定: カメラの遮蔽と復帰がその描画で表示距離をどう決めたかの枝。計器が読み、表示距離の決定と一緒に運ぶ。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 遮蔽の判定 {
    遮られていない,                 // 注視点から理想視点までの掃引が何にも触れなかった
    遮られている,                   // 掃引が世界の形に触れ、表示距離を理想距離より手前へ寄せた
    評価できず前の表示距離を保った, // 掃引の答えが評価できない領域を含み、前の描画の表示距離をそのまま使った
}
