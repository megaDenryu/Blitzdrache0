//! プレイヤーの状態: 位置と向きの対と移動状態を1つにまとめ、1刻みぶんの移動と向きの回転を行う。
//! キツネの場所巡りと歩くだけのゲームの両方がこの1つを持ち、ゲームごとに移動を書き分けない(判断14)。
//!
//! 位置と向きと移動状態を対で持つのは、移動で位置だけを更新して移動状態を置き去りにする書き方を通さないためである。

use blitz_design::{M不変データ, M問い合わせを伴う遷移関数, M状態, 問い合わせを伴う遷移の結果, 問い合わせを伴う遷移成功結果, 遷移失敗結果};
use blitz_math::大域メートル;

use crate::世界の形::{世界の形を尋ねる口, 口の実装が決める失敗の代表, 口の実装を代表する口};
use crate::位置と向き::プレイヤーの位置と向き;
use crate::向いている方位角::動く個体が向いている方位角;
use crate::操作意図の命令::胴体の移動の操作;
use crate::移動::移動の観測;
use crate::移動::移動状態;
use crate::移動::胴体の移動;
use crate::移動::胴体の移動の遷移パラメータ;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct プレイヤーの状態 {
    位置と向き: プレイヤーの位置と向き,
    移動状態: 移動状態,
}

impl M不変データ for プレイヤーの状態 {}
impl M状態 for プレイヤーの状態 {}

impl プレイヤーの状態 {
    /// 出発地点に立たせる。接地はまだ確かめていないため空中で静止した状態から始め、最初の刻みの接地判定に委ねる。
    pub fn 開始時の状態を作る(出発地点: blitz_math::大域ワールド位置, 出発時の向き: 動く個体が向いている方位角) -> Self {
        Self {
            位置と向き: プレイヤーの位置と向き::生成する(出発地点, 出発時の向き),
            移動状態: 移動状態::開始時は空中で静止している(),
        }
    }

    pub fn 位置と向き(self) -> プレイヤーの位置と向き {
        self.位置と向き
    }

    pub fn 移動状態(self) -> 移動状態 {
        self.移動状態
    }

    /// 胴体の移動の操作で1刻みぶん動かした状態と、その刻みの移動の観測を返す。位置と移動状態は胴体の移動が、向きは倒した向きへの回転が決める。
    /// 問い合わせが失敗したら、受け取った状態を書き換えずに口の失敗と一緒に返す。
    pub fn 胴体の移動の操作で動かした状態を返す<口: 世界の形を尋ねる口 + ?Sized>(
        self,
        操作: &胴体の移動の操作,
        規則: &胴体の移動,
        入力: 胴体の移動の遷移パラメータ,
        口: &mut 口,
    ) -> 問い合わせを伴う遷移の結果<Self, 移動の観測, 口::問い合わせエラー> {
        let 結果 = match 規則.足元と移動状態を動かす(口, self.位置と向き.大域位置(), self.移動状態, 操作, &入力) {
            Ok(結果) => 結果,
            Err(失敗の理由) => return Err(遷移失敗結果 { 元の状態: self, 失敗の理由 }),
        };
        let 位置と向き = self.位置と向き.足元を据えた位置と向きを返す(結果.足元()).倒した向きへ回る速さの上限まで回した位置と向きを返す(操作, &入力, 規則.回る速さ());
        Ok(問い合わせを伴う遷移成功結果 {
            次の状態: Self {
                位置と向き, 移動状態: 結果.移動状態()
            },
            観測: 結果.観測(),
        })
    }

    // 天頂成分を据え直し、移動状態を空中で静止した開始時の値へ戻した状態。刻みを経ずに位置を跳ばす据え直しが使う。
    // 移動状態を戻すのは、跳ばした先の接地を次の刻みの接地判定に改めて決めさせるためである。
    pub(crate) fn 天頂成分を据え直した状態を返す(self, 天頂成分: 大域メートル) -> Self {
        Self {
            位置と向き: self.位置と向き.天頂成分を据えた位置と向きを返す(天頂成分),
            移動状態: 移動状態::開始時は空中で静止している(),
        }
    }
}

// 胴体の移動の操作で動かした状態を返す が、問い合わせを伴う遷移の役割を満たすことをコンパイラに確かめさせる。問い合わせ先と失敗は代表で具体化し、実際の失敗は口の実装が決める。
const _: M問い合わせを伴う遷移関数<プレイヤーの状態, 胴体の移動の操作, 胴体の移動, 胴体の移動の遷移パラメータ, 口の実装を代表する口, 移動の観測, 口の実装が決める失敗の代表> =
    M問い合わせを伴う遷移関数::生成する(プレイヤーの状態::胴体の移動の操作で動かした状態を返す);
