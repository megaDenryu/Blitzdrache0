//! 世界の形を尋ねる口: ゲームロジック層が自分の語彙で定めた、世界の形へ問いを渡して答えを受け取るトレイト。
//!
//! トレイトにするのは実装が2つあるためである。コンポジションルートのゲーム配線が持つ実装はエンジンの世界の形への
//! 問い合わせを包み、ゲームロジック層の検査が持つ実装は平面と段と壁だけの世界である。既存の高さ場の写しと同じ形であり、
//! 違いは「答えを写す」だけでなく「問いを渡す」向きが加わることである。
//!
//! 問い合わせが型付きエラーで失敗したら握り潰さず上へ返す。エラーの型を実装ごとに持たせるのは、エンジンの問い合わせが
//! 拒む理由をゲームロジック層が名指しできないためである。検査の世界は失敗しないため`Infallible`を置く。
//! `&mut self`で受けるのは、配線の実装が候補の受け皿を持って使い回すためである。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断3」

use blitz_math::{メートル, ワールド, 変位, 大域ワールド位置};

use crate::掃引の答えの対::掃引の答え;
use crate::胴体の形::胴体カプセル;

pub trait 世界の形を尋ねる口 {
    type 問い合わせエラー: std::error::Error;

    /// 胴体カプセルを掃引の変位だけ動かしたとき、最初に触れる面を求める。
    fn 掃引した胴体が最初に触れる面を求める(&mut self, 胴体: 胴体カプセル, 掃引の変位: 変位<ワールド>) -> Result<掃引の答え, Self::問い合わせエラー>;

    /// 中心と半径で決まる球を掃引の変位だけ動かしたとき、最初に触れる面を求める。軸の長さ0のカプセルである。
    fn 掃引した球が最初に触れる面を求める(&mut self, 中心: 大域ワールド位置, 半径: メートル, 掃引の変位: 変位<ワールド>) -> Result<掃引の答え, Self::問い合わせエラー>;
}

/// 関数の役割の宣言だけに使う、口の実装ごとの問い合わせエラーの代表。実際の失敗の型は口の実装が決め(コンポジションルートの口では
/// `世界の形を尋ねる口の実装エラー`、検査の世界では失敗しない)、ゲームロジック層からは名指せないため、宣言にはこの代表を書く。
/// 宣言を読んで関数が失敗しないと読まないこと。関数は口の実装の失敗をそのまま遷移失敗結果に入れて返す(参照: `_doc/設計/設計オントロジー.md` 第3節)。
pub(crate) type 口の実装が決める失敗の代表 = std::convert::Infallible;

/// 関数の役割の宣言だけに使う、世界の形を尋ねる口の代表。問い合わせ先を型引数に取るジェネリックな関数を関数ポインタへ写すとき具体の型が1つ要り、
/// ゲームロジック層の中で名指せる具体の口はトレイトのオブジェクトだけであるため、この代表で具体化する。実際の口とその失敗は名指さない。
pub(crate) type 口の実装を代表する口 = dyn 世界の形を尋ねる口<問い合わせエラー = 口の実装が決める失敗の代表>;
