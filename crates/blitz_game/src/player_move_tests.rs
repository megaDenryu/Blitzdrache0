//! 前へ進む向きを変えたときに移動がどちらへ向くかの検査。反証したいのは、移動がワールド軸に固定されたままで
//! カメラの向きを変えても同じ方角へ歩いてしまうことである。姿勢の検査は`player_move_facing_tests`にある。
//! 世界は床だけの世界であり、足元は床の上に据えてから動かす。

use blitz_math::{ラジアン, 大域メートル, 大域ワールド位置, 秒};

use crate::facing_azimuth::動く個体が向いている方位角;
use crate::forward_azimuth::前へ進む向きの方位角;
use crate::game_intent::ゲームインテント;
use crate::movement::一刻みの移動の入力;
use crate::operation_axis::操作軸の倒し量;
use crate::planar_test_world::平面と段と壁の世界;
use crate::player_state::プレイヤーの状態;

const 一刻み: f32 = 1.0 / 60.0;
/// 位置の比較に許す誤差。1刻みで進む距離が約0.067メートルであるため、この幅は向きの取り違えを見逃さない。
const 許す誤差メートル: f64 = 1.0e-6;

fn 前へ倒したインテント() -> ゲームインテント {
    ゲームインテント {
        前後の倒し量: 操作軸の倒し量::押下の対から生成する(true, false),
        ..ゲームインテント::無操作()
    }
}

fn 右へ倒したインテント() -> ゲームインテント {
    ゲームインテント {
        左右の倒し量: 操作軸の倒し量::押下の対から生成する(true, false),
        ..ゲームインテント::無操作()
    }
}

fn 一刻み動かす(状態: プレイヤーの状態, 入力: &一刻みの移動の入力) -> プレイヤーの状態 {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0));
    match 状態.一刻み動かした状態を返す(&mut 世界, 入力) {
        Ok((次, _)) => 次,
        Err(誤り) => match 誤り {},
    }
}

/// 原点の床の上に北を向いて立った状態から1刻み動かし、原点から見た足元の変位を返す。
pub(crate) fn 一刻み動かした位置(
    インテント: ゲームインテント, 前へ進む向き: 前へ進む向きの方位角
) -> 大域ワールド位置 {
    let 立った = 一刻み動かす(
        プレイヤーの状態::開始時の状態を作る(大域ワールド位置::原点(), 動く個体が向いている方位角::北を向く()),
        &一刻みの移動の入力 {
            インテント: ゲームインテント::無操作(),
            刻み: 秒::生成する(一刻み),
            前へ進む向き,
        },
    );
    let 動いた = 一刻み動かす(
        立った,
        &一刻みの移動の入力 {
            インテント,
            刻み: 秒::生成する(一刻み),
            前へ進む向き,
        },
    );
    動いた.位置と向き().大域位置().平行移動する(大域ワールド位置::生成する(
        大域メートル::生成する(-立った.位置と向き().大域位置().x().値()),
        大域メートル::生成する(-立った.位置と向き().大域位置().y().値()),
        大域メートル::生成する(-立った.位置と向き().大域位置().z().値()),
    ))
}

fn 西を指す向き() -> 前へ進む向きの方位角 {
    前へ進む向きの方位角::生成する(ラジアン::度から(90.0))
}

#[test]
fn 北を向いて前へ倒すと北へ動く() {
    let 位置 = 一刻み動かした位置(前へ倒したインテント(), 前へ進む向きの方位角::北を指す());
    assert!(位置.z().値() < -許す誤差メートル);
    assert!(位置.x().値().abs() < 許す誤差メートル);
}

#[test]
fn 西を向いて前へ倒すと西へ動く() {
    let 位置 = 一刻み動かした位置(前へ倒したインテント(), 西を指す向き());
    assert!(位置.x().値() < -許す誤差メートル);
    assert!(位置.z().値().abs() < 許す誤差メートル);
}

/// 前が西のとき右は北である。右へ倒したときに東へ動くなら、右の向きが前の向きに追従していない。
#[test]
fn 西を向いて右へ倒すと北へ動く() {
    let 位置 = 一刻み動かした位置(右へ倒したインテント(), 西を指す向き());
    assert!(位置.z().値() < -許す誤差メートル);
    assert!(位置.x().値().abs() < 許す誤差メートル);
}

/// 反証: 斜めに倒したときの速さが軸1本より速いと、斜め移動が近道になる。
#[test]
fn 斜めに倒しても一刻みで進む距離が軸一本と変わらない() {
    let 斜め = ゲームインテント {
        前後の倒し量: 操作軸の倒し量::押下の対から生成する(true, false),
        左右の倒し量: 操作軸の倒し量::押下の対から生成する(true, false),
        ..ゲームインテント::無操作()
    };
    let 斜めの位置 = 一刻み動かした位置(斜め, 前へ進む向きの方位角::北を指す());
    let 軸一本の位置 = 一刻み動かした位置(前へ倒したインテント(), 前へ進む向きの方位角::北を指す());
    let 斜めの距離 = (斜めの位置.x().値().powi(2) + 斜めの位置.z().値().powi(2)).sqrt();
    let 軸一本の距離 = (軸一本の位置.x().値().powi(2) + 軸一本の位置.z().値().powi(2)).sqrt();
    assert!((斜めの距離 - 軸一本の距離).abs() < 許す誤差メートル);
}
