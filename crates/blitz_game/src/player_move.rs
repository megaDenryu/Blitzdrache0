//! プレイヤーが1刻みで動いた後の大域位置を求める工程を所有する。受け取るのは今の大域位置と操作の意図と刻みと前へ進む向き、
//! 返すのは移動後の大域位置だけであり、進行段階も場所巡りも知らない。
//!
//! 移動をワールド軸に固定せず前へ進む向きを受け取るのは、画面の上へ倒したときにキツネが画面の奥へ歩くようにするためである。
//! 向きをどこから決めるか(カメラの方位なのか、固定の方位なのか)はコンポジションルートの配線が決める。

use blitz_math::{メートル毎秒, 大域メートル, 大域ワールド位置, 秒};

use crate::forward_azimuth::前へ進む向きの方位角;
use crate::game_intent::ゲームインテント;

/// プレイヤーが歩く速さ。人が早歩きする程度の値を置き、地形の高さを読む工程が入るまではこの1つだけで動く。
fn プレイヤーの歩く速さ() -> メートル毎秒 {
    メートル毎秒::生成する(4.0)
}

/// 移動後のプレイヤーの大域位置を求める。
///
/// 倒し量の長さが1を超えるときだけ縮めるのは、斜めに倒したときの速さが軸1本のときより速くならないようにするためである。
pub fn 移動後のプレイヤーの大域位置を求める(
    今の大域位置: 大域ワールド位置,
    インテント: ゲームインテント,
    刻み: 秒,
    前へ進む向き: 前へ進む向きの方位角,
) -> 大域ワールド位置 {
    let 右への倒し量 = インテント.左右の倒し量.値();
    let 前への倒し量 = インテント.前後の倒し量.値();
    let 倒し量の長さ = (右への倒し量 * 右への倒し量 + 前への倒し量 * 前への倒し量).sqrt();
    if 倒し量の長さ <= 0.0 {
        return 今の大域位置;
    }
    let 縮める倍率 = if 倒し量の長さ > 1.0 { 1.0 / 倒し量の長さ } else { 1.0 };
    let 進む距離 = プレイヤーの歩く速さ() * 刻み;
    let 倍率 = 縮める倍率 * 進む距離.値();
    let (前の東成分, 前の南成分) = 前へ進む向き.前へ進む向きの東と南の成分();
    let (右の東成分, 右の南成分) = 前へ進む向き.右へ寄る向きの東と南の成分();
    let 東へのずれ = f64::from((前への倒し量 * 前の東成分 + 右への倒し量 * 右の東成分) * 倍率);
    let 南へのずれ = f64::from((前への倒し量 * 前の南成分 + 右への倒し量 * 右の南成分) * 倍率);
    今の大域位置.平行移動する(大域ワールド位置::生成する(
        大域メートル::生成する(東へのずれ),
        大域メートル::生成する(0.0),
        大域メートル::生成する(南へのずれ),
    ))
}
