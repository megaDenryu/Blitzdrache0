//! プレイヤーの位置と向きの1刻みぶんの更新を所有する。触れるのは`プレイヤーの位置と向き`が持つ大域位置と向きの対だけであり、
//! 進行段階も場所巡りも移動状態も知らない。担当は2つである。胴体の移動が決めた足元を据えること、倒した向きへ向きを回すことである。
//!
//! 倒していないフレームを除く判定をここへ閉じるのは、歩いていないのに向きだけ回る状態を1箇所で防ぐためである。
//! 向きをどこから決めるか(カメラの方位なのか、固定の方位なのか)はコンポジションルートの配線が決める。

use blitz_math::{ラジアン毎秒, 大域ワールド位置};

use crate::movement::一刻みの移動の入力;
use crate::movement::世界の軸で見た倒し量;
use crate::player_placement::プレイヤーの位置と向き;

impl プレイヤーの位置と向き {
    // 足元の大域位置だけを胴体の移動が決めた値へ据え、向きはそのままにした位置と向き。
    pub(crate) fn 足元を据えた位置と向きを返す(self, 足元: 大域ワールド位置) -> Self {
        Self::生成する(足元, self.向き())
    }

    // 倒した向きへ1刻みで回れる角を上限に回した位置と向き。倒していない刻みは向きを動かさない。
    pub(crate) fn 倒した向きへ一刻みぶん回した位置と向きを返す(
        self,
        入力: &一刻みの移動の入力,
        回る速さ: ラジアン毎秒,
    ) -> Self {
        if 世界の軸で見た倒し量::生成する(入力.インテント, 入力.前へ進む向き).中立か() {
            return self;
        }
        let 目標の向き = 入力
            .前へ進む向き
            .倒し量が指す向きを求める(入力.インテント.左右の倒し量.値(), 入力.インテント.前後の倒し量.値());
        Self::生成する(
            self.大域位置(),
            self.向き().目標の向きへ一刻みぶん回した向きを返す(目標の向き, 回る速さ, 入力.刻み),
        )
    }
}
