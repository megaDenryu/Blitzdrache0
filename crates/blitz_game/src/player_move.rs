//! プレイヤーが1刻みで動いた後の位置と向きを求める工程を所有する。受け取るのは今の位置と向きと操作の意図と刻みと前へ進む向き、
//! 返すのは移動後の位置と向きだけであり、進行段階も場所巡りも知らない。
//!
//! 位置と向きを1つの工程で求めるのは、どちらもそのフレームに倒した向き1つから決まるためである。分けて置くと、
//! 倒していないフレームを除く判定が2箇所に分かれ、片方だけを直すと歩いていないのに向きだけ回る状態になる。
//!
//! 移動をワールド軸に固定せず前へ進む向きを受け取るのは、画面の上へ倒したときにキツネが画面の奥へ歩くようにするためである。
//! 向きをどこから決めるか(カメラの方位なのか、固定の方位なのか)はコンポジションルートの配線が決める。

use blitz_math::{メートル毎秒, ラジアン毎秒, 大域メートル, 大域ワールド位置, 秒};

use crate::forward_azimuth::前へ進む向きの方位角;
use crate::game_intent::ゲームインテント;
use crate::player_placement::プレイヤーの位置と向き;

/// プレイヤーが歩く速さ。人が早歩きする程度の値を置き、地形の高さを読む工程が入るまではこの1つだけで動く。
fn プレイヤーの歩く速さ() -> メートル毎秒 {
    メートル毎秒::生成する(4.0)
}

/// プレイヤーが向きを変える速さ。毎秒720度では真後ろへの向き直りが0.25秒(15フレーム)で終わり、
/// 向きが変わる過程が絵に残りつつ、操作から遅れて見えない。
fn プレイヤーが回る速さ() -> ラジアン毎秒 {
    ラジアン毎秒::度毎秒から(720.0)
}

/// 移動後のプレイヤーの位置と向きを求める。
///
/// 倒し量の長さが1を超えるときだけ縮めるのは、斜めに倒したときの速さが軸1本のときより速くならないようにするためである。
pub fn 移動後のプレイヤーの位置と向きを求める(
    今の位置と向き: プレイヤーの位置と向き,
    インテント: ゲームインテント,
    刻み: 秒,
    前へ進む向き: 前へ進む向きの方位角,
) -> プレイヤーの位置と向き {
    let 右への倒し量 = インテント.左右の倒し量.値();
    let 前への倒し量 = インテント.前後の倒し量.値();
    let 倒し量の長さ = (右への倒し量 * 右への倒し量 + 前への倒し量 * 前への倒し量).sqrt();
    if 倒し量の長さ <= 0.0 {
        return 今の位置と向き;
    }
    let 縮める倍率 = if 倒し量の長さ > 1.0 { 1.0 / 倒し量の長さ } else { 1.0 };
    let 進む距離 = プレイヤーの歩く速さ() * 刻み;
    let 倍率 = 縮める倍率 * 進む距離.値();
    let (前の東成分, 前の南成分) = 前へ進む向き.前へ進む向きの東と南の成分();
    let (右の東成分, 右の南成分) = 前へ進む向き.右へ寄る向きの東と南の成分();
    let 東へのずれ = f64::from((前への倒し量 * 前の東成分 + 右への倒し量 * 右の東成分) * 倍率);
    let 南へのずれ = f64::from((前への倒し量 * 前の南成分 + 右への倒し量 * 右の南成分) * 倍率);
    let ずれ = 大域ワールド位置::生成する(
        大域メートル::生成する(東へのずれ),
        大域メートル::生成する(0.0),
        大域メートル::生成する(南へのずれ),
    );
    let 目標の向き = 前へ進む向き.倒し量が指す向きを求める(右への倒し量, 前への倒し量);
    プレイヤーの位置と向き::生成する(
        今の位置と向き.大域位置().平行移動する(ずれ),
        今の位置と向き
            .向き()
            .目標の向きへ一刻みぶん回した向きを返す(目標の向き, プレイヤーが回る速さ(), 刻み),
    )
}
