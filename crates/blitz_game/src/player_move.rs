//! プレイヤーが1刻みで動いた後の大域位置を求める工程を所有する。受け取るのは今の大域位置と操作の意図と刻み、
//! 返すのは移動後の大域位置だけであり、進行段階も場所巡りも知らない。
//!
//! ワールド軸はXが東、Yが天頂、Zが南であり、北はZの負の向きである(`_doc/計画/ユビキタス言語.md`「太陽方向」が定める軸)。
//! 前へ進む操作は北へ動くため、Zは倒し量の符号を反転して足す。

use blitz_math::{メートル毎秒, 大域メートル, 大域ワールド位置, 秒};

use crate::game_intent::ゲームインテント;

/// プレイヤーが歩く速さ。人が早歩きする程度の値を置き、地形の高さを読む工程が入るまではこの1つだけで動く。
fn プレイヤーの歩く速さ() -> メートル毎秒 {
    メートル毎秒::生成する(4.0)
}

/// 移動後のプレイヤーの大域位置を求める。
///
/// 倒し量の長さが1を超えるときだけ縮めるのは、斜めに倒したときの速さが軸1本のときより速くならないようにするためである。
pub fn 移動後のプレイヤーの大域位置を求める(
    今の大域位置: 大域ワールド位置,
    インテント: ゲームインテント,
    刻み: 秒,
) -> 大域ワールド位置 {
    let 東への倒し量 = インテント.左右の倒し量.値();
    let 北への倒し量 = インテント.前後の倒し量.値();
    let 倒し量の長さ = (東への倒し量 * 東への倒し量 + 北への倒し量 * 北への倒し量).sqrt();
    if 倒し量の長さ <= 0.0 {
        return 今の大域位置;
    }
    let 縮める倍率 = if 倒し量の長さ > 1.0 { 1.0 / 倒し量の長さ } else { 1.0 };
    let 進む距離 = プレイヤーの歩く速さ() * 刻み;
    let 東へのずれ = f64::from(東への倒し量 * 縮める倍率 * 進む距離.値());
    let 北へのずれ = f64::from(北への倒し量 * 縮める倍率 * 進む距離.値());
    今の大域位置.平行移動する(大域ワールド位置::生成する(
        大域メートル::生成する(東へのずれ),
        大域メートル::生成する(0.0),
        大域メートル::生成する(-北へのずれ),
    ))
}
