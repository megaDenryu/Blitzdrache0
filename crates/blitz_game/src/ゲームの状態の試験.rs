//! 1刻みの更新の検査。段階の移りと移動と到達判定が1つの刻みでどう噛み合うかを見る。世界は床だけの世界である。

use blitz_math::{メートル, 大域メートル, 大域ワールド位置, 秒};

use crate::ゲームの状態::場所巡りのゲームの状態;
use crate::前へ進む向き::前へ進む向きの方位角;
use crate::向いている方位角::動く個体が向いている方位角;
use crate::巡る目的地::目的地;
use crate::操作意図::ゲームの操作意図;
use crate::検査用の世界::平面と段と壁の世界;
use crate::確定済みの入力::{押した瞬間の操作の入力, 押しっぱなし操作入力, 確定済みの操作入力};
use crate::移動::{胴体の移動, 胴体の移動の状態遷移パラメータ};
use crate::進行段階::ゲームの進行段階;
use crate::道順::場所巡りの道順;

const 基本刻みの秒: f32 = 1.0 / 60.0;

/// 出発地点が原点で、北を向いて立っている開始の状態。
fn 開始の状態() -> 場所巡りのゲームの状態 {
    場所巡りのゲームの状態::開始時の状態を作る(大域ワールド位置::原点(), 動く個体が向いている方位角::北を向く())
}

/// 出発地点の北へ1メートルの位置に、半径0.5メートルの目的地を1つ置いた道順。
fn 検査用の道順() -> 場所巡りの道順 {
    let 北へ一メートル = 大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(0.0), 大域メートル::生成する(-1.0));
    場所巡りの道順::生成する(vec![目的地::生成する(北へ一メートル, メートル::生成する(0.5))])
}

/// 検査の呼び出しの包み。規則の3つの変換を固定刻みの工程と同じ順(状態遷移→移動→到達判定)で呼び、移動と到達判定は
/// `移動と到達判定を行う段階か`が真の刻みだけ行う。前へ進む向きは常に北であり、向きを変えたときの移動は`前へ進む向きと移動の試験`が見る。
fn 北を向いて固定刻みを1つ進める(状態: &場所巡りのゲームの状態, 意図: ゲームの操作意図, 刻み秒: f32) -> 場所巡りのゲームの状態 {
    let 状態遷移後 = 状態.操作の意図で進行段階を状態遷移させた状態を返す(&意図.進行の操作());
    if !状態遷移後.進行段階().移動と到達判定を行う段階か() {
        return 状態遷移後;
    }
    let 入力 = 胴体の移動の状態遷移パラメータ::生成する(秒::生成する(刻み秒), 前へ進む向きの方位角::北を指す());
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0));
    let 移動後 = match 状態遷移後.プレイヤーを胴体の移動の命令の組で動かした状態を返す(&意図.胴体の移動の命令の組(), &胴体の移動::初版の値で生成する(), 入力, &mut 世界) {
        Ok(成功) => 成功.次の状態,
        Err(失敗) => match 失敗.失敗の理由 {},
    };
    移動後.目的地への到達を判定して場所巡りの進行を進めた状態を返す(&検査用の道順())
}

fn 前へ進む意図() -> ゲームの操作意図 {
    ゲームの操作意図::確定済みの操作入力から写す(確定済みの操作入力::生成する(
        押しっぱなし操作入力::無操作().前へ進む操作を押しているかを置き換えた入力(true),
        押した瞬間の操作の入力::無操作(),
    ))
}

fn 決定だけの意図() -> ゲームの操作意図 {
    ゲームの操作意図::確定済みの操作入力から写す(確定済みの操作入力::生成する(
        押しっぱなし操作入力::無操作(),
        押した瞬間の操作の入力::無操作().決定操作を押した瞬間かを置き換えた入力(true),
    ))
}

/// 反証: タイトル表示中に移動が効くと、メニューの裏で世界が進む。向きも同じであり、タイトルの絵でキツネが回り出してはならない。
#[test]
fn タイトル表示中は移動しても位置も向きも変わらない() {
    let 開始 = 開始の状態();
    let 次 = 北を向いて固定刻みを1つ進める(&開始, 前へ進む意図(), 基本刻みの秒);
    assert_eq!(次.進行段階(), ゲームの進行段階::タイトル表示中);
    assert_eq!(次.プレイヤーの大域位置(), 大域ワールド位置::原点());
    assert_eq!(次.プレイヤーの向き(), 開始.プレイヤーの向き());
}

/// 反証: 移動を行うかの判定が状態遷移前の進行段階を読むと、決定と前進を同時に含む刻みで場所巡り中に入りながら位置が動かない。
#[test]
fn 決定で場所巡りへ入った刻みから移動が効く() {
    let 決定と前進を同時に含む意図 = ゲームの操作意図::確定済みの操作入力から写す(確定済みの操作入力::生成する(
        押しっぱなし操作入力::無操作().前へ進む操作を押しているかを置き換えた入力(true),
        押した瞬間の操作の入力::無操作().決定操作を押した瞬間かを置き換えた入力(true),
    ));
    let 開始 = 開始の状態();
    let 遊び始めながら一歩進んだ状態 = 北を向いて固定刻みを1つ進める(&開始, 決定と前進を同時に含む意図, 基本刻みの秒);
    assert_eq!(遊び始めながら一歩進んだ状態.進行段階(), ゲームの進行段階::場所巡り中);
    assert!(遊び始めながら一歩進んだ状態.プレイヤーの大域位置().z().値() < 0.0);
}

#[test]
fn 北へ歩き続けると目的地へ到達する() {
    let 開始 = 開始の状態();
    let mut 状態 = 北を向いて固定刻みを1つ進める(&開始, 決定だけの意図(), 基本刻みの秒);
    for _ in 0..60 {
        状態 = 北を向いて固定刻みを1つ進める(&状態, 前へ進む意図(), 基本刻みの秒);
    }
    assert!(状態.場所巡り().全ての目的地へ到達したか(&検査用の道順()));
}

/// 反証: 刻みが0でも位置が動くと、時計を止めた実行で世界が進む。
#[test]
fn 刻みが零なら位置が動かない() {
    let 開始 = 開始の状態();
    let 状態 = 北を向いて固定刻みを1つ進める(&開始, 決定だけの意図(), 基本刻みの秒);
    let 次 = 北を向いて固定刻みを1つ進める(&状態, 前へ進む意図(), 0.0);
    assert_eq!(次.プレイヤーの大域位置(), 状態.プレイヤーの大域位置());
}

#[test]
fn 終了確認で決定すると終了が決まる() {
    let キャンセル = ゲームの操作意図::確定済みの操作入力から写す(確定済みの操作入力::生成する(
        押しっぱなし操作入力::無操作(),
        押した瞬間の操作の入力::無操作().キャンセル操作を押した瞬間かを置き換えた入力(true),
    ));
    let 開始 = 開始の状態();
    let 確認中 = 北を向いて固定刻みを1つ進める(&開始, キャンセル, 基本刻みの秒);
    let 終了 = 北を向いて固定刻みを1つ進める(&確認中, 決定だけの意図(), 基本刻みの秒);
    assert!(終了.終了が決まったか());
}
