//! 水平の稜: 検査用の世界で、床の東端と東へ下る斜面の西端が出会う、南北に走る1本の水平な線。担当するのは、球が
//! この線へ触れる時刻と、その接触を掃引の接触へ写すことである。半空間の面は自分の範囲の外の接触を持たないため、
//! 球が床の東端を越えて斜面の面に届くまでの間の接触はこの稜だけが答える。実際の地形の三角形が稜で持つ接触と同じ形である。
//!
//! 接触は面へ向かう掃引だけが持つ。稜への接触の単位法線は稜の上の最近接点から球の中心へ向かう向きであり、
//! 変位とその向きの内積が負でなければ触れない(`half_space_face`と同じ幅で平行を捨てる)。
//! 南の範囲で有効な部分を限れるのは、南端で終わる段の角を斜めに抜ける検査のためである。範囲の判定は接触点(稜の上の最近接点)で行う。

use crate::half_space_face::{内積, 大域位置, 平行とみなす余弦の幅, 進めた点, 面の範囲};
use crate::moved_fraction::動けた割合;
use crate::sweep_contact::掃引の接触;
use blitz_math::方向;

#[derive(Debug, Clone, Copy)]
pub(super) struct 水平の稜 {
    pub(super) 東: f64,
    pub(super) 高さ: f64,
    pub(super) 範囲: 面の範囲,
}

impl 水平の稜 {
    // 球の中心が始点から変位だけ動くとき、この稜へ触れる時刻。稜へ向かわない掃引は値なしである。
    pub(super) fn 球が触れる時刻(&self, 中心: [f64; 3], 半径: f64, 変位: [f64; 3]) -> Option<f64> {
        let 始まりの隔たり = self.稜から中心への変位(中心);
        let 二次 = 変位[0] * 変位[0] + 変位[1] * 変位[1];
        let 一次 = 2.0 * (始まりの隔たり[0] * 変位[0] + 始まりの隔たり[1] * 変位[1]);
        let 定数 = 内積(始まりの隔たり, 始まりの隔たり) - 半径 * 半径;
        if 定数 <= 0.0 {
            return ((内積(変位, 変位) == 0.0 || self.向かうか(中心, 変位)) && self.範囲.内側か(self.最近接点(中心))).then_some(0.0);
        }
        let 判別式 = 一次 * 一次 - 4.0 * 二次 * 定数;
        if 二次 <= 0.0 || 判別式 < 0.0 {
            return None;
        }
        let 時刻 = (-一次 - 判別式.sqrt()) / (2.0 * 二次);
        let 触れた中心 = 進めた点(中心, 変位, 時刻);
        ((0.0..=1.0).contains(&時刻) && self.向かうか(触れた中心, 変位) && self.範囲.内側か(self.最近接点(触れた中心))).then_some(時刻)
    }

    fn 最近接点(&self, 中心: [f64; 3]) -> [f64; 3] {
        [self.東, self.高さ, 中心[2]]
    }

    // 触れた時刻の球の表面のうち稜へ最も近い点を接触の位置にする。
    pub(super) fn 接触を組む(&self, 時刻: f64, 中心: [f64; 3], 半径: f64, 変位: [f64; 3]) -> 掃引の接触 {
        let 触れた中心 = 進めた点(中心, 変位, 時刻);
        let 法線 = self.稜から中心への単位向き(触れた中心);
        let 接触点 = [触れた中心[0] - 法線[0] * 半径, 触れた中心[1] - 法線[1] * 半径, 触れた中心[2]];
        let 割合 = 動けた割合::倍精度から生成する(時刻)
            .unwrap_or_else(|誤り| panic!("稜へ触れる時刻が動けた割合の範囲を外れた(不変条件が破れている): {誤り}"));
        let 方向 = 方向::倍精度の成分から生成する(法線[0], 法線[1], 法線[2])
            .unwrap_or_else(|誤り| panic!("稜への接触の法線が単位方向でない(不変条件が破れている): {誤り}"));
        掃引の接触::生成する(割合, 大域位置(接触点), 方向)
    }

    fn 向かうか(&self, 中心: [f64; 3], 変位: [f64; 3]) -> bool {
        let 向き = self.稜から中心への単位向き(中心);
        -内積(変位, 向き) > 平行とみなす余弦の幅 * 内積(変位, 変位).sqrt()
    }

    fn 稜から中心への変位(&self, 中心: [f64; 3]) -> [f64; 3] {
        [中心[0] - self.東, 中心[1] - self.高さ, 0.0]
    }

    // 中心が稜のちょうど上に在り向きが定まらないときは真上を向く。
    fn 稜から中心への単位向き(&self, 中心: [f64; 3]) -> [f64; 3] {
        let 変位 = self.稜から中心への変位(中心);
        let 長さ = 内積(変位, 変位).sqrt();
        if 長さ <= 0.0 {
            return [0.0, 1.0, 0.0];
        }
        [変位[0] / 長さ, 変位[1] / 長さ, 0.0]
    }
}
