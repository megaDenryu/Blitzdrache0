//! 移動の1刻みが姿勢をどう動かすかの検査。反証したいのは、歩いた向きへ姿勢が追わずキツネが横や後ろを向いたまま滑ることと、
//! 立ち止まっているのに向きが回り続けることである。回す角そのものの検査は`facing_azimuth_tests`にある。

use blitz_math::{ラジアン, 大域ワールド位置, 秒};

use crate::facing_azimuth::動く個体が向いている方位角;
use crate::forward_azimuth::前へ進む向きの方位角;
use crate::game_intent::ゲームインテント;
use crate::operation_axis::操作軸の倒し量;
use crate::player_placement::プレイヤーの位置と向き;

const 一刻み: f32 = 1.0 / 60.0;
/// 向きの比較に許す誤差。1刻みで回れる角が12度であるため、この幅は回る向きの取り違えを見逃さない。
const 許す誤差度: f32 = 1.0e-3;

fn 前へ倒したインテント() -> ゲームインテント {
    ゲームインテント {
        前後の倒し量: 操作軸の倒し量::押下の対から生成する(true, false),
        ..ゲームインテント::無操作()
    }
}

fn 右へ倒したインテント() -> ゲームインテント {
    ゲームインテント {
        左右の倒し量: 操作軸の倒し量::押下の対から生成する(true, false),
        ..ゲームインテント::無操作()
    }
}

/// 原点で北を向いて立っている姿勢から1刻みだけ動かし、動いた後の向きを度で読む。
fn 北を向いた姿勢から一刻み動かした向きの度(
    インテント: ゲームインテント, 前へ進む向き: 前へ進む向きの方位角
) -> f32 {
    let 北を向いた姿勢 = プレイヤーの位置と向き::生成する(大域ワールド位置::原点(), 動く個体が向いている方位角::北を向く());
    let 移動後 = 北を向いた姿勢.移動後の位置と向きを返す(インテント, 秒::生成する(一刻み), 前へ進む向き);
    移動後.向き().ラジアンで表した角().値().to_degrees()
}

fn 西を指す向き() -> 前へ進む向きの方位角 {
    前へ進む向きの方位角::生成する(ラジアン::度から(90.0))
}

/// 反証: 倒していないフレームで向きが動くと、立ち止まったキツネがその場で回り続ける。
#[test]
fn 倒していないフレームでは向きが変わらない() {
    let 向きの度 = 北を向いた姿勢から一刻み動かした向きの度(ゲームインテント::無操作(), 西を指す向き());
    assert!(向きの度.abs() < 許す誤差度);
}

/// 北を向いた姿勢から西へ歩き出すフレームでは、1刻みで回れる12度だけ西へ回る。西は方位角の正の側である。
#[test]
fn 横へ歩き出したフレームは一刻みで回れる角だけ回る() {
    let 向きの度 = 北を向いた姿勢から一刻み動かした向きの度(前へ倒したインテント(), 西を指す向き());
    assert!((向きの度 - 12.0).abs() < 許す誤差度);
}

/// 反証: 右へ倒したときに前の向きのままだと、キツネが横歩きになる。前が北のとき右へ倒せば東を向く。
#[test]
fn 右へ倒したフレームは東側へ回る() {
    let 向きの度 = 北を向いた姿勢から一刻み動かした向きの度(右へ倒したインテント(), 前へ進む向きの方位角::北を指す());
    assert!((向きの度 + 12.0).abs() < 許す誤差度);
}
