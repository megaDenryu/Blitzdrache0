//! 遮蔽の判定の入力: カメラの遮蔽と復帰が1描画に1度受け取る値の束。
//!
//! 表示距離の下限を入力で受けるのは、その値がエンジンのオービットカメラの最小距離であり、ゲームロジック層が
//! 写しの定数を持つと2つ目の所有者になるためである。進めた時間は実時間でなく、その描画で進めた刻み数に基本刻みを掛けた値である。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断10」「判断12」

use blitz_math::{メートル, 大域ワールド位置, 秒};

use crate::previous_display_distance::前の描画の表示距離;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 遮蔽の判定の入力 {
    pub 注視点: 大域ワールド位置,         // 混ぜた足元の位置に目の高さを足した点
    pub 理想視点: 大域ワールド位置,       // ヨー・ピッチ・理想距離が決める、遮蔽を考えない視点
    pub 理想距離: メートル,               // 注視点から理想視点までの距離
    pub 表示距離の下限: メートル,         // オービットカメラの最小距離
    pub 前の表示距離: 前の描画の表示距離, // 復帰の基準と、評価できない描画で保つ値
    pub 進めた時間: 秒,                   // その描画で進めた刻み数に基本刻みを掛けた時間
}
