//! カメラの復帰とズームの検査。遮蔽が消えた後は毎秒8メートルで理想距離へ戻ること・理想距離を越えないこと・
//! 利用者の理想距離の変化(ズーム)は遮蔽が無ければ同じ描画で通ること・遮蔽からの回復だけが遅れることを固定する。
//! 構図は `遮蔽の試験の構図` を見る。

use blitz_math::メートル;

use crate::遮蔽の判定の選択肢::遮蔽の判定;
use crate::遮蔽の試験の構図::{self, 基本刻みの秒};

/// 反証: 遮蔽が消えた瞬間に理想距離へ跳ぶと、視点が不連続に動く。1刻みで伸びるのは毎秒8メートルの1/60である。
#[test]
fn 遮蔽が消えると表示距離は毎秒8メートルで理想距離へ戻る() {
    let (表示距離, 判定) = 遮蔽の試験の構図::表示距離と判定を決める(&mut 遮蔽の試験の構図::壁の無い世界(), 遮蔽の試験の構図::判定の入力(8.0, 遮蔽の試験の構図::描いた前の描画(3.75, 8.0)));
    assert_eq!(判定, 遮蔽の判定::遮られていない);
    assert_eq!(表示距離, メートル::生成する(3.75) + メートル::生成する(8.0 * 基本刻みの秒));
}

#[test]
fn 復帰は理想距離を越えない() {
    let (表示距離, _) = 遮蔽の試験の構図::表示距離と判定を決める(&mut 遮蔽の試験の構図::壁の無い世界(), 遮蔽の試験の構図::判定の入力(8.0, 遮蔽の試験の構図::描いた前の描画(7.95, 8.0)));
    assert_eq!(表示距離, メートル::生成する(8.0));
}

/// 反証: 前の表示距離をそのまま基準にすると、遮蔽が無くてもズームアウトが毎秒8メートルでしか進まず、ホイールの操作が数描画遅れる。
#[test]
fn 遮蔽が無ければ理想距離を増やした描画で表示距離は理想距離に追いつく() {
    let (表示距離, 判定) = 遮蔽の試験の構図::表示距離と判定を決める(&mut 遮蔽の試験の構図::壁の無い世界(), 遮蔽の試験の構図::判定の入力(10.56, 遮蔽の試験の構図::描いた前の描画(9.6, 9.6)));
    assert_eq!(判定, 遮蔽の判定::遮られていない);
    assert_eq!(表示距離, メートル::生成する(10.56));
}

#[test]
fn 理想距離を減らした描画で表示距離は同じ描画で縮む() {
    let (表示距離, _) = 遮蔽の試験の構図::表示距離と判定を決める(&mut 遮蔽の試験の構図::壁の無い世界(), 遮蔽の試験の構図::判定の入力(6.0, 遮蔽の試験の構図::描いた前の描画(8.0, 8.0)));
    assert_eq!(表示距離, メートル::生成する(6.0));
}

/// 反証: 理想距離の変化を基準に足さないと、遮蔽で縮んでいる間のズームアウトが回復の終わりまで見えない。
/// 反証: 基準を理想距離へ跳ばすと、遮蔽からの回復も一緒に跳んで判断10の一定の速さが破れる。
/// 反証: 理想距離の減ったぶんを基準から引くと、遮蔽で縮んでいる間のズームインで基準が壁の許す3.75メートルより縮み、
/// そこから毎秒8メートルで戻る揺れが数描画だけ出る。壁の許す距離は理想距離に依らないため、表示距離は同じ描画で3.75メートルのままである。
#[test]
fn 遮蔽で縮んでいる間に理想距離を減らしても表示距離は壁の許す距離のまま揺れない() {
    let (表示距離, 判定) = 遮蔽の試験の構図::表示距離と判定を決める(&mut 遮蔽の試験の構図::南4メートルに壁のある世界(), 遮蔽の試験の構図::判定の入力(7.0, 遮蔽の試験の構図::描いた前の描画(3.75, 8.0)));
    assert_eq!(判定, 遮蔽の判定::遮られている);
    assert!((表示距離.値() - 3.75).abs() < 1e-5, "表示距離が{}メートルになった", 表示距離.値());
}

#[test]
fn 遮蔽で縮んだ後に理想距離を増やしても回復は毎秒8メートルのままである() {
    let (表示距離, _) = 遮蔽の試験の構図::表示距離と判定を決める(&mut 遮蔽の試験の構図::壁の無い世界(), 遮蔽の試験の構図::判定の入力(9.0, 遮蔽の試験の構図::描いた前の描画(3.75, 8.0)));
    assert_eq!(表示距離, メートル::生成する(4.75) + メートル::生成する(8.0 * 基本刻みの秒));
}
