//! 歩くだけのゲームが持つプレイヤーの位置と向き。進行段階・目的地・道順を持たない。

use blitz_math::{大域ワールド位置, 秒};

use crate::{
    ゲームインテント, プレイヤーの位置と向き, 前へ進む向きの方位角, 動く個体が向いている方位角, 足元の地面の高さ
};

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 歩くだけのゲームの状態 {
    プレイヤー: プレイヤーの位置と向き,
}

impl 歩くだけのゲームの状態 {
    pub fn 開始時の状態を作る(出発地点: 大域ワールド位置, 出発時の向き: 動く個体が向いている方位角) -> Self {
        Self {
            プレイヤー: プレイヤーの位置と向き::生成する(出発地点, 出発時の向き),
        }
    }

    pub fn 一刻み進めた状態を返す(
        self, インテント: ゲームインテント, 刻み: 秒, 前へ進む向き: 前へ進む向きの方位角
    ) -> Self {
        Self {
            プレイヤー: crate::player_move::移動後のプレイヤーの位置と向きを求める(
                self.プレイヤー,
                インテント,
                刻み,
                前へ進む向き,
            ),
        }
    }

    pub fn 足元の地面の高さを反映した状態を返す(self, 地面の高さ: 足元の地面の高さ) -> Self {
        let 足元の地面の高さ::高さ場から参照した高さ(高さ) = 地面の高さ else {
            return self;
        };
        Self {
            プレイヤー: self.プレイヤー.天頂成分を据えた位置と向きを返す(高さ),
        }
    }

    pub fn プレイヤーの位置と向き(self) -> プレイヤーの位置と向き {
        self.プレイヤー
    }
}
