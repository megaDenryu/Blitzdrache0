//! 胴体カプセル: プレイヤーの胴体を、足元の点から鉛直に立てた1本の軸と半径で表す形。
//!
//! 位置の正本は足元の点のままであり、軸の両端はそこから導く。寸法はキツネの標準サンプルを100分の1にした実寸に合わせた
//! 初版の値であり、実機で調整する。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断4」

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};

const 初版の半径メートル: f32 = 0.25;
const 初版の軸の下端の高さメートル: f32 = 0.25;
const 初版の軸の上端の高さメートル: f32 = 0.55;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 胴体カプセル {
    足元の位置: 大域ワールド位置,
    半径: メートル,
    軸の下端の高さ: メートル, // 足元から軸の下端までの高さ
    軸の上端の高さ: メートル, // 足元から軸の上端までの高さ
}

impl 胴体カプセル {
    /// 初版の寸法(半径0.25メートル・軸の下端0.25メートル・上端0.55メートル)で足元へ立てる。
    pub fn 初版の寸法で足元へ立てる(足元の位置: 大域ワールド位置) -> Self {
        Self {
            足元の位置,
            半径: メートル::生成する(初版の半径メートル),
            軸の下端の高さ: メートル::生成する(初版の軸の下端の高さメートル),
            軸の上端の高さ: メートル::生成する(初版の軸の上端の高さメートル),
        }
    }

    /// 軸の下端の位置から、初版の寸法で足元を導いて立てる。接地判定が触れた瞬間の足元を接触の位置から組むときに使う。
    pub fn 初版の寸法で軸の下端へ立てる(軸の下端の位置: 大域ワールド位置) -> Self {
        Self::初版の寸法で足元へ立てる(軸の下端の位置.平行移動する(大域ワールド位置::生成する(
            大域メートル::生成する(0.0),
            大域メートル::生成する(-f64::from(初版の軸の下端の高さメートル)),
            大域メートル::生成する(0.0),
        )))
    }

    pub fn 足元の位置(&self) -> 大域ワールド位置 {
        self.足元の位置
    }

    pub fn 半径(&self) -> メートル {
        self.半径
    }

    pub fn 軸の下端の大域位置(&self) -> 大域ワールド位置 {
        self.足元から上へ(self.軸の下端の高さ)
    }

    pub fn 軸の上端の大域位置(&self) -> 大域ワールド位置 {
        self.足元から上へ(self.軸の上端の高さ)
    }

    fn 足元から上へ(&self, 高さ: メートル) -> 大域ワールド位置 {
        self.足元の位置.平行移動する(大域ワールド位置::生成する(
            大域メートル::生成する(0.0),
            大域メートル::生成する(f64::from(高さ.値())),
            大域メートル::生成する(0.0),
        ))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 軸の両端は足元の真上に立つ() {
        let 足元 = 大域ワールド位置::生成する(大域メートル::生成する(3.0), 大域メートル::生成する(1.0), 大域メートル::生成する(-2.0));
        let 胴体 = 胴体カプセル::初版の寸法で足元へ立てる(足元);
        assert_eq!(胴体.軸の下端の大域位置().y(), 大域メートル::生成する(1.0 + f64::from(0.25_f32)));
        assert_eq!(胴体.軸の上端の大域位置().y(), 大域メートル::生成する(1.0 + f64::from(0.55_f32)));
        assert_eq!(胴体.軸の上端の大域位置().x(), 足元.x());
        assert_eq!(胴体.軸の上端の大域位置().z(), 足元.z());
        assert_eq!(胴体.半径(), メートル::生成する(0.25));
    }

    #[test]
    fn 軸の下端から立てた胴体の足元は下端の真下にある() {
        let 下端 = 大域ワールド位置::生成する(大域メートル::生成する(3.0), 大域メートル::生成する(1.25), 大域メートル::生成する(-2.0));
        let 胴体 = 胴体カプセル::初版の寸法で軸の下端へ立てる(下端);
        assert_eq!(胴体.足元の位置().y(), 大域メートル::生成する(1.0));
        assert_eq!(胴体.軸の下端の大域位置(), 下端);
    }
}
