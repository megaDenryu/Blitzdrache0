//! プレイヤーが世界のどこに、どちらを向いて立っているかを1つの値として所有する。触れるのは位置と向きの対だけであり、
//! 進行段階も場所巡りも知らない。
//!
//! 位置と向きを別々のフィールドで持ち回らないのは、動く個体を描く側がこの2つを常に対で受け取るためである。
//! 分けて持つと、移動で位置だけを更新して向きを置き去りにする書き方が通ってしまう。
//!
//! 1刻みぶんの更新(足元を据えること、倒した向きへ向きを回すこと)もこの型のメソッドとして持つ。
//! 倒していないフレームを除く判定をここへ閉じるのは、歩いていないのに向きだけ回る状態を1箇所で防ぐためである。
//! 向きをどこから決めるか(カメラの方位なのか、固定の方位なのか)はコンポジションルートの配線が決める。

use blitz_design::{M不変データ, M値オブジェクト};
use blitz_math::{ラジアン毎秒, 大域メートル, 大域ワールド位置};

use crate::facing_azimuth::動く個体が向いている方位角;
use crate::movement::一刻みの移動の入力;
use crate::movement::世界の軸で見た倒し量;

/// プレイヤーの立ち位置と姿勢の対。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct プレイヤーの位置と向き {
    大域位置: 大域ワールド位置,
    向き: 動く個体が向いている方位角,
}

impl M不変データ for プレイヤーの位置と向き {}
impl M値オブジェクト for プレイヤーの位置と向き {}

impl プレイヤーの位置と向き {
    pub fn 生成する(大域位置: 大域ワールド位置, 向き: 動く個体が向いている方位角) -> Self {
        Self { 大域位置, 向き }
    }

    pub fn 大域位置(self) -> 大域ワールド位置 {
        self.大域位置
    }

    pub fn 向き(self) -> 動く個体が向いている方位角 {
        self.向き
    }

    /// 天頂成分だけを据え直した位置と向きを返す。地面の高さを反映する工程が使う。水平の2成分と向きは動かない。
    pub(crate) fn 天頂成分を据えた位置と向きを返す(self, 天頂成分: 大域メートル) -> Self {
        Self {
            大域位置: 大域ワールド位置::生成する(self.大域位置.x(), 天頂成分, self.大域位置.z()),
            ..self
        }
    }

    // 足元の大域位置だけを胴体の移動が決めた値へ据え、向きはそのままにした位置と向き。
    pub(crate) fn 足元を据えた位置と向きを返す(self, 足元: 大域ワールド位置) -> Self {
        Self::生成する(足元, self.向き())
    }

    // 倒した向きへ1刻みで回れる角を上限に回した位置と向き。倒していない刻みは向きを動かさない。
    pub(crate) fn 倒した向きへ一刻みぶん回した位置と向きを返す(self, 入力: &一刻みの移動の入力, 回る速さ: ラジアン毎秒) -> Self {
        if 世界の軸で見た倒し量::生成する(入力.意図, 入力.前へ進む向き).中立か() {
            return self;
        }
        let 目標の向き = 入力.前へ進む向き.倒し量が指す向きを求める(入力.意図.左右の倒し量.値(), 入力.意図.前後の倒し量.値());
        Self::生成する(self.大域位置(), self.向き().目標の向きへ一刻みぶん回した向きを返す(目標の向き, 回る速さ, 入力.刻み))
    }
}
