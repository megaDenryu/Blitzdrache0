//! プレイヤーが世界のどこに、どちらを向いて立っているかを1つの値として所有する。触れるのは位置と向きの対だけであり、
//! 進行段階も場所巡りも知らない。
//!
//! 位置と向きを別々のフィールドで持ち回らないのは、動く個体を描く側がこの2つを常に対で受け取るためである。
//! 分けて持つと、移動で位置だけを更新して向きを置き去りにする書き方が通ってしまう。

use blitz_math::{大域メートル, 大域ワールド位置};

use crate::facing_azimuth::動く個体が向いている方位角;

/// プレイヤーの立ち位置と姿勢の対。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct プレイヤーの位置と向き {
    大域位置: 大域ワールド位置,
    向き: 動く個体が向いている方位角,
}

impl プレイヤーの位置と向き {
    pub fn 生成する(大域位置: 大域ワールド位置, 向き: 動く個体が向いている方位角) -> Self {
        Self { 大域位置, 向き }
    }

    pub fn 大域位置(self) -> 大域ワールド位置 {
        self.大域位置
    }

    pub fn 向き(self) -> 動く個体が向いている方位角 {
        self.向き
    }

    /// 天頂成分だけを据え直した位置と向きを返す。地面の高さを反映する工程が使う。水平の2成分と向きは動かない。
    pub(crate) fn 天頂成分を据えた位置と向きを返す(self, 天頂成分: 大域メートル) -> Self {
        Self {
            大域位置: 大域ワールド位置::生成する(self.大域位置.x(), 天頂成分, self.大域位置.z()),
            ..self
        }
    }
}
