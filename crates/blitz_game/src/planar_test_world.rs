//! 平面と段と壁だけの世界。検査が世界の形を尋ねる口の実装として使い、エンジンの問い合わせを1つも要らずに
//! 遮蔽と移動の規則を固定する。
//!
//! 床は全域の水平面、壁は範囲を持たない北向きの鉛直面、段は東端より東だけで有効な高い床と、段の高さより下だけで有効な
//! 鉛直面(蹴上げ)の対である。床の東端から東へ下る斜面は、東端より東だけで有効な面と、床と斜面が出会う水平の稜の対である。評価できない領域は東の境界より東であり、掃引の覆いがそこへ達した問いは
//! 「何にも触れない」を評価できない領域を含む完全性で返す(エンジンの問い合わせが接触を捨てる規律と同じ)。
//! 胴体カプセルは軸の両端の球の掃引の早いほうで答える。面が平面だけの世界ではこれが厳密な答えである。
//! 接触は面へ向かう掃引だけが持つ(エンジンの掃引と同じ規則。`half_space_face`)。
//! 壁・段・斜面・評価できない領域を置く組み立ては`builders`にある。

mod builders;

use blitz_math::{メートル, ワールド, 変位, 大域メートル, 大域ワールド位置};

use crate::body_capsule::胴体カプセル;
use crate::crest_edge::水平の稜;
use crate::half_space_face::{半空間の面, 面の範囲};
use crate::sweep_answer::掃引の答え;
use crate::sweep_completeness::掃引の完全性;
use crate::sweep_hit::掃引が最初に触れる面;
use crate::world_shape_port::世界の形を尋ねる口;

pub(crate) struct 平面と段と壁の世界 {
    面一覧: Vec<半空間の面>,
    稜一覧: Vec<水平の稜>,
    評価できない東の境界: Option<f64>, // 検査の世界だけが持つ設定であり、値なしは評価できない領域が無いことを表す
}

impl 平面と段と壁の世界 {
    pub(crate) fn 床だけの世界(床の高さ: 大域メートル) -> Self {
        Self::床の世界(床の高さ, 面の範囲::全域)
    }

    // 東端より西だけに床がある世界。東端から東へ下る斜面を置き、床から斜面へ入る稜を作る検査が使う。
    pub(crate) fn 西側だけ床の世界(床の高さ: 大域メートル, 東端: 大域メートル) -> Self {
        Self::床の世界(床の高さ, 面の範囲::東がこれ以下(東端.値()))
    }

    fn 床の世界(床の高さ: 大域メートル, 範囲: 面の範囲) -> Self {
        Self {
            面一覧: vec![半空間の面 {
                法線: [0.0, 1.0, 0.0],
                閾値: 床の高さ.値(),
                範囲,
            }],
            稜一覧: Vec::new(),
            評価できない東の境界: None,
        }
    }

    fn 覆いが評価できない領域に達するか(&self, 中心一覧: &[[f64; 3]], 半径: f64, 変位: [f64; 3]) -> bool {
        let Some(境界) = self.評価できない東の境界 else {
            return false;
        };
        中心一覧.iter().any(|中心| 中心[0] + 半径 >= 境界 || 中心[0] + 変位[0] + 半径 >= 境界)
    }

    // 中心ごと・面ごと・稜ごとの接触の時刻のうち最小のものを答える。時刻が並んだときは面を先に、並びの先の中心を先に残す。
    fn 答えを組む(&self, 中心一覧: &[[f64; 3]], 半径: f64, 変位: [f64; 3]) -> 掃引の答え {
        if self.覆いが評価できない領域に達するか(中心一覧, 半径, 変位) {
            return 掃引の答え::生成する(掃引が最初に触れる面::何にも触れない, 掃引の完全性::評価できない領域を含む);
        }
        let 面の接触 = 中心一覧
            .iter()
            .flat_map(|中心| self.面一覧.iter().map(move |面| (面, *中心)))
            .filter_map(|(面, 中心)| {
                面.球が触れる時刻(中心, 半径, 変位)
                    .map(|時刻| (時刻, 面.接触を組む(時刻, 中心, 半径, 変位)))
            });
        let 稜の接触 = 中心一覧
            .iter()
            .flat_map(|中心| self.稜一覧.iter().map(move |稜| (稜, *中心)))
            .filter_map(|(稜, 中心)| {
                稜.球が触れる時刻(中心, 半径, 変位)
                    .map(|時刻| (時刻, 稜.接触を組む(時刻, 中心, 半径, 変位)))
            });
        let 面 = match 面の接触.chain(稜の接触).min_by(|(左, _), (右, _)| 左.total_cmp(右)) {
            None => 掃引が最初に触れる面::何にも触れない,
            Some((_, 接触)) => 掃引が最初に触れる面::触れる(接触),
        };
        掃引の答え::生成する(面, 掃引の完全性::対象範囲を完全に評価できた)
    }
}

impl 世界の形を尋ねる口 for 平面と段と壁の世界 {
    type 問い合わせエラー = std::convert::Infallible;

    fn 掃引した胴体が最初に触れる面を求める(
        &mut self,
        胴体: 胴体カプセル,
        掃引の変位: 変位<ワールド>,
    ) -> Result<掃引の答え, Self::問い合わせエラー> {
        let 両端 = [成分(胴体.軸の下端の大域位置()), 成分(胴体.軸の上端の大域位置())];
        Ok(self.答えを組む(&両端, f64::from(胴体.半径().値()), 変位の成分(掃引の変位)))
    }

    fn 掃引した球が最初に触れる面を求める(
        &mut self,
        中心: 大域ワールド位置,
        半径: メートル,
        掃引の変位: 変位<ワールド>,
    ) -> Result<掃引の答え, Self::問い合わせエラー> {
        Ok(self.答えを組む(&[成分(中心)], f64::from(半径.値()), 変位の成分(掃引の変位)))
    }
}

fn 成分(位置: 大域ワールド位置) -> [f64; 3] {
    [位置.x().値(), 位置.y().値(), 位置.z().値()]
}

fn 変位の成分(変位: 変位<ワールド>) -> [f64; 3] {
    [f64::from(変位.x().値()), f64::from(変位.y().値()), f64::from(変位.z().値())]
}
