//! 1刻みの更新の検査。段階の移りと移動と到達判定が1つの刻みでどう噛み合うかを見る。

use blitz_math::{メートル, 大域メートル, 大域ワールド位置, 秒};

use crate::destination::目的地;
use crate::facing_azimuth::動く個体が向いている方位角;
use crate::forward_azimuth::前へ進む向きの方位角;
use crate::game_intent::ゲームインテント;
use crate::game_state::場所巡りのゲームの状態;
use crate::operation_axis::操作軸の倒し量;
use crate::progress_stage::ゲームの進行段階;
use crate::tour_route::場所巡りの道順;

const 一刻み: f32 = 1.0 / 60.0;

/// 出発地点が原点で、北を向いて立っている開始の状態。
fn 開始の状態() -> 場所巡りのゲームの状態 {
    場所巡りのゲームの状態::開始時の状態を作る(大域ワールド位置::原点(), 動く個体が向いている方位角::北を向く())
}

/// 出発地点の北へ1メートルの位置に、半径0.5メートルの目的地を1つ置いた道順。
fn 検査用の道順() -> 場所巡りの道順 {
    let 北へ一メートル =
        大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(0.0), 大域メートル::生成する(-1.0));
    場所巡りの道順::生成する(vec![目的地::生成する(北へ一メートル, メートル::生成する(0.5))])
}

/// 検査の呼び出しの包み。前へ進む向きは常に北であり、向きを変えたときの移動は`player_move_tests`が見る。
fn 北を向いて一刻み進める(
    状態: &場所巡りのゲームの状態, 意図: ゲームインテント, 刻み秒: f32
) -> 場所巡りのゲームの状態 {
    状態.一刻み進めた状態を返す(&検査用の道順(), 意図, 秒::生成する(刻み秒), 前へ進む向きの方位角::北を指す())
}

fn 前へ進むインテント() -> ゲームインテント {
    ゲームインテント {
        前後の倒し量: 操作軸の倒し量::押下の対から生成する(true, false),
        ..ゲームインテント::無操作()
    }
}

fn 決定だけのインテント() -> ゲームインテント {
    ゲームインテント {
        決定を押したか: true,
        ..ゲームインテント::無操作()
    }
}

/// 反証: タイトル表示中に移動が効くと、メニューの裏で世界が進む。向きも同じであり、タイトルの絵でキツネが回り出してはならない。
#[test]
fn タイトル表示中は移動しても位置も向きも変わらない() {
    let 開始 = 開始の状態();
    let 次 = 北を向いて一刻み進める(&開始, 前へ進むインテント(), 一刻み);
    assert_eq!(次.進行段階(), ゲームの進行段階::タイトル表示中);
    assert_eq!(次.プレイヤーの大域位置(), 大域ワールド位置::原点());
    assert_eq!(次.プレイヤーの向き(), 開始.プレイヤーの向き());
}

#[test]
fn 決定で場所巡りへ入った刻みから移動が効く() {
    let 開始 = 開始の状態();
    let 遊び始めた状態 = 北を向いて一刻み進める(&開始, 決定だけのインテント(), 一刻み);
    assert_eq!(遊び始めた状態.進行段階(), ゲームの進行段階::場所巡り中);
    let 一歩進んだ状態 = 北を向いて一刻み進める(&遊び始めた状態, 前へ進むインテント(), 一刻み);
    assert!(一歩進んだ状態.プレイヤーの大域位置().z().値() < 0.0);
}

#[test]
fn 北へ歩き続けると目的地へ到達する() {
    let 開始 = 開始の状態();
    let mut 状態 = 北を向いて一刻み進める(&開始, 決定だけのインテント(), 一刻み);
    for _ in 0..60 {
        状態 = 北を向いて一刻み進める(&状態, 前へ進むインテント(), 一刻み);
    }
    assert!(状態.場所巡り().全ての目的地へ到達したか(&検査用の道順()));
}

/// 反証: 刻みが0でも位置が動くと、時計を止めた実行で世界が進む。
#[test]
fn 刻みが零なら位置が動かない() {
    let 開始 = 開始の状態();
    let 状態 = 北を向いて一刻み進める(&開始, 決定だけのインテント(), 一刻み);
    let 次 = 北を向いて一刻み進める(&状態, 前へ進むインテント(), 0.0);
    assert_eq!(次.プレイヤーの大域位置(), 状態.プレイヤーの大域位置());
}

#[test]
fn 終了確認で決定すると終了が決まる() {
    let キャンセル = ゲームインテント {
        キャンセルを押したか: true,
        ..ゲームインテント::無操作()
    };
    let 開始 = 開始の状態();
    let 確認中 = 北を向いて一刻み進める(&開始, キャンセル, 一刻み);
    let 終了 = 北を向いて一刻み進める(&確認中, 決定だけのインテント(), 一刻み);
    assert!(終了.終了が決まったか());
}
