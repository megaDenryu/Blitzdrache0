//! 1刻みの更新の検査。段階の移りと移動と到達判定が1つの刻みでどう噛み合うかを見る。

use blitz_math::{メートル, 大域メートル, 大域ワールド位置, 秒};

use crate::destination::目的地;
use crate::game_intent::ゲームインテント;
use crate::game_state::場所巡りのゲームの状態;
use crate::operation_axis::操作軸の倒し量;
use crate::progress_stage::ゲームの進行段階;
use crate::tour_route::場所巡りの道順;

const 一刻み: f32 = 1.0 / 60.0;

fn 原点() -> 大域ワールド位置 {
    大域ワールド位置::原点()
}

/// 出発地点の北へ1メートルの位置に、半径0.5メートルの目的地を1つ置いた道順。
fn 検査用の道順() -> 場所巡りの道順 {
    let 北へ一メートル =
        大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(0.0), 大域メートル::生成する(-1.0));
    場所巡りの道順::生成する(vec![目的地::生成する(北へ一メートル, メートル::生成する(0.5))])
}

fn 前へ進むインテント() -> ゲームインテント {
    ゲームインテント {
        前後の倒し量: 操作軸の倒し量::押下の対から生成する(true, false),
        ..ゲームインテント::無操作()
    }
}

fn 決定だけのインテント() -> ゲームインテント {
    ゲームインテント {
        決定を押したか: true,
        ..ゲームインテント::無操作()
    }
}

/// 反証: タイトル表示中に移動が効くと、メニューの裏で世界が進む。
#[test]
fn タイトル表示中は移動しても位置が変わらない() {
    let 状態 = 場所巡りのゲームの状態::開始時の状態を作る(原点());
    let 次 = 状態.一刻み進めた状態を返す(&検査用の道順(), 前へ進むインテント(), 秒::生成する(一刻み));
    assert_eq!(次.進行段階(), ゲームの進行段階::タイトル表示中);
    assert_eq!(次.プレイヤーの大域位置(), 原点());
}

#[test]
fn 決定で場所巡りへ入った刻みから移動が効く() {
    let 道順 = 検査用の道順();
    let 状態 = 場所巡りのゲームの状態::開始時の状態を作る(原点());
    let 遊び始めた状態 = 状態.一刻み進めた状態を返す(&道順, 決定だけのインテント(), 秒::生成する(一刻み));
    assert_eq!(遊び始めた状態.進行段階(), ゲームの進行段階::場所巡り中);
    let 一歩進んだ状態 = 遊び始めた状態.一刻み進めた状態を返す(&道順, 前へ進むインテント(), 秒::生成する(一刻み));
    assert!(一歩進んだ状態.プレイヤーの大域位置().z().値() < 0.0);
}

#[test]
fn 北へ歩き続けると目的地へ到達する() {
    let 道順 = 検査用の道順();
    let mut 状態 =
        場所巡りのゲームの状態::開始時の状態を作る(原点()).一刻み進めた状態を返す(&道順, 決定だけのインテント(), 秒::生成する(一刻み));
    for _ in 0..60 {
        状態 = 状態.一刻み進めた状態を返す(&道順, 前へ進むインテント(), 秒::生成する(一刻み));
    }
    assert!(状態.場所巡り().全ての目的地へ到達したか(&道順));
}

/// 反証: 刻みが0でも位置が動くと、時計を止めた実行で世界が進む。
#[test]
fn 刻みが零なら位置が動かない() {
    let 道順 = 検査用の道順();
    let 状態 =
        場所巡りのゲームの状態::開始時の状態を作る(原点()).一刻み進めた状態を返す(&道順, 決定だけのインテント(), 秒::生成する(一刻み));
    let 次 = 状態.一刻み進めた状態を返す(&道順, 前へ進むインテント(), 秒::生成する(0.0));
    assert_eq!(次.プレイヤーの大域位置(), 状態.プレイヤーの大域位置());
}

#[test]
fn 終了確認で決定すると終了が決まる() {
    let 道順 = 検査用の道順();
    let キャンセル = ゲームインテント {
        キャンセルを押したか: true,
        ..ゲームインテント::無操作()
    };
    let 確認中 = 場所巡りのゲームの状態::開始時の状態を作る(原点()).一刻み進めた状態を返す(&道順, キャンセル, 秒::生成する(一刻み));
    let 終了 = 確認中.一刻み進めた状態を返す(&道順, 決定だけのインテント(), 秒::生成する(一刻み));
    assert!(終了.終了が決まったか());
}
