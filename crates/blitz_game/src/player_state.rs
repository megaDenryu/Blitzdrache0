//! プレイヤーの状態: 位置と向きの対と移動状態を1つにまとめ、1刻みぶんの移動と向きの回転を行う。
//! キツネの場所巡りと歩くだけのゲームの両方がこの1つを持ち、ゲームごとに移動を書き分けない(判断14)。
//!
//! 位置と向きと移動状態を対で持つのは、移動で位置だけを更新して移動状態を置き去りにする書き方を通さないためである。

use blitz_math::大域メートル;

use crate::facing_azimuth::動く個体が向いている方位角;
use crate::movement::一刻みの移動の入力;
use crate::movement::移動の観測;
use crate::movement::移動状態;
use crate::movement::胴体の移動;
use crate::player_placement::プレイヤーの位置と向き;
use crate::world_shape_port::世界の形を尋ねる口;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct プレイヤーの状態 {
    位置と向き: プレイヤーの位置と向き,
    移動状態: 移動状態,
}

impl プレイヤーの状態 {
    /// 出発地点に立たせる。接地はまだ確かめていないため空中で静止した状態から始め、最初の刻みの接地判定に委ねる。
    pub fn 開始時の状態を作る(
        出発地点: blitz_math::大域ワールド位置, 出発時の向き: 動く個体が向いている方位角
    ) -> Self {
        Self {
            位置と向き: プレイヤーの位置と向き::生成する(出発地点, 出発時の向き),
            移動状態: 移動状態::開始時は空中で静止している(),
        }
    }

    pub fn 位置と向き(self) -> プレイヤーの位置と向き {
        self.位置と向き
    }

    pub fn 移動状態(self) -> 移動状態 {
        self.移動状態
    }

    /// 1刻みぶん動かした状態と、その刻みの移動の観測を返す。位置と移動状態は胴体の移動が、向きは倒した向きへの回転が決める。
    pub fn 一刻み動かした状態を返す<口: 世界の形を尋ねる口>(
        self,
        口: &mut 口,
        入力: &一刻みの移動の入力,
    ) -> Result<(Self, 移動の観測), 口::問い合わせエラー> {
        let 規則 = 胴体の移動::初版の値で生成する();
        let 結果 = 規則.一刻み動かす(口, self.位置と向き.大域位置(), self.移動状態, 入力)?;
        let 位置と向き = self
            .位置と向き
            .足元を据えた位置と向きを返す(結果.足元())
            .倒した向きへ一刻みぶん回した位置と向きを返す(入力, 規則.回る速さ());
        Ok((
            Self {
                位置と向き,
                移動状態: 結果.移動状態(),
            },
            結果.観測(),
        ))
    }

    /// 天頂成分を据え直し、移動状態を空中で静止した開始時の値へ戻した状態。刻みを経ずに位置を跳ばす据え直しが使う。
    /// 移動状態を戻すのは、跳ばした先の接地を次の刻みの接地判定に改めて決めさせるためである。
    pub(crate) fn 天頂成分を据え直した状態を返す(self, 天頂成分: 大域メートル) -> Self {
        Self {
            位置と向き: self.位置と向き.天頂成分を据えた位置と向きを返す(天頂成分),
            移動状態: 移動状態::開始時は空中で静止している(),
        }
    }
}
