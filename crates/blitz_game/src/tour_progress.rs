//! どこまで巡ったかの進行を所有する。触れるのは次に向かう目的地の番号だけであり、目的地の位置と半径は道順の側が持つ。

use blitz_math::大域ワールド位置;

use crate::tour_route::{場所巡りの道順, 目的地番号};

/// 場所巡りがどこまで進んだか。次に向かう目的地の番号が道順の総数に達した状態が全踏破である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 場所巡りの進行 {
    次に向かう目的地の番号: 目的地番号,
}

impl 場所巡りの進行 {
    /// まだ1つも巡っていない進行。
    pub fn 出発前の進行を作る() -> Self {
        Self {
            次に向かう目的地の番号: 目的地番号::最初(),
        }
    }

    /// 到達済みの目的地の数。番号が0なら0件であり、番号がそのまま件数になる。
    pub fn 到達済みの目的地数(&self) -> usize {
        self.次に向かう目的地の番号.添字()
    }

    pub fn 全ての目的地へ到達したか(&self, 道順: &場所巡りの道順) -> bool {
        self.到達済みの目的地数() >= 道順.目的地の総数()
    }

    /// 次に向かう目的地へ到達していれば1つ進めた進行を返し、していなければそのままの進行を返す。
    ///
    /// 1回の呼び出しで進むのは高々1つである。次の目的地の位置を読まずに判定を打ち切るのは、
    /// 目的地が近接して置かれたときに1フレームで複数を飛ばして巡ったことにしないためである。
    pub fn 到達を判定して進めた進行を返す(
        &self, 道順: &場所巡りの道順, プレイヤーの大域位置: 大域ワールド位置
    ) -> Self {
        let Some(目的地) = 道順.番号の目的地を参照する(self.次に向かう目的地の番号) else {
            return *self;
        };
        if !目的地.到達したとみなせるか(プレイヤーの大域位置) {
            return *self;
        }
        Self {
            次に向かう目的地の番号: self.次に向かう目的地の番号.次の番号(),
        }
    }
}
