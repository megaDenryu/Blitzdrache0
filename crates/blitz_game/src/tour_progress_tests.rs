//! 場所巡りの到達判定と進行の検査。半径の内と外、全踏破の後、1回で複数を飛ばさないことを見る。

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};

use crate::destination::目的地;
use crate::tour_progress::場所巡りの進行;
use crate::tour_route::場所巡りの道順;

fn 東の位置(東メートル: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(東メートル),
        大域メートル::生成する(0.0),
        大域メートル::生成する(0.0),
    )
}

/// 東へ10メートルおきに2つ、半径1メートルの目的地を置いた道順。
fn 検査用の道順() -> 場所巡りの道順 {
    場所巡りの道順::生成する(vec![
        目的地::生成する(東の位置(10.0), メートル::生成する(1.0)),
        目的地::生成する(東の位置(20.0), メートル::生成する(1.0)),
    ])
}

/// 反証: 半径の外でも進むと、目的地へ行かずに全踏破できる。
#[test]
fn 半径の外では進行が変わらない() {
    let 道順 = 検査用の道順();
    let 進行 = 場所巡りの進行::出発前の進行を作る();
    let 次 = 進行.到達を判定して進めた進行を返す(&道順, 東の位置(8.0));
    assert_eq!(次.到達済みの目的地数(), 0);
}

#[test]
fn 半径の内で1つ進む() {
    let 道順 = 検査用の道順();
    let 進行 = 場所巡りの進行::出発前の進行を作る();
    let 次 = 進行.到達を判定して進めた進行を返す(&道順, 東の位置(10.5));
    assert_eq!(次.到達済みの目的地数(), 1);
    assert!(!次.全ての目的地へ到達したか(&道順));
}

#[test]
fn 半径のちょうど境界は到達とみなす() {
    let 道順 = 検査用の道順();
    let 進行 = 場所巡りの進行::出発前の進行を作る();
    let 次 = 進行.到達を判定して進めた進行を返す(&道順, 東の位置(11.0));
    assert_eq!(次.到達済みの目的地数(), 1);
}

/// 反証: 1回の判定で列を走査すると、目的地を通らずに複数を飛ばして巡ったことになる。
#[test]
fn 一度の判定で進むのは高々一つ() {
    let 道順 = 場所巡りの道順::生成する(vec![
        目的地::生成する(東の位置(10.0), メートル::生成する(50.0)),
        目的地::生成する(東の位置(20.0), メートル::生成する(50.0)),
    ]);
    let 進行 = 場所巡りの進行::出発前の進行を作る();
    let 次 = 進行.到達を判定して進めた進行を返す(&道順, 東の位置(15.0));
    assert_eq!(次.到達済みの目的地数(), 1);
}

#[test]
fn 全ての目的地へ到達すると全踏破になりそれ以上進まない() {
    let 道順 = 検査用の道順();
    let mut 進行 = 場所巡りの進行::出発前の進行を作る();
    進行 = 進行.到達を判定して進めた進行を返す(&道順, 東の位置(10.0));
    進行 = 進行.到達を判定して進めた進行を返す(&道順, 東の位置(20.0));
    assert!(進行.全ての目的地へ到達したか(&道順));
    let さらに進めた進行 = 進行.到達を判定して進めた進行を返す(&道順, 東の位置(20.0));
    assert_eq!(さらに進めた進行.到達済みの目的地数(), 2);
}

/// 高さの差を距離に数えないと、目的地の真上を通っただけで到達が成立する。
#[test]
fn 高さの差が半径を超えると到達しない() {
    let 道順 = 検査用の道順();
    let 高い位置 = 大域ワールド位置::生成する(大域メートル::生成する(10.0), 大域メートル::生成する(5.0), 大域メートル::生成する(0.0));
    let 進行 = 場所巡りの進行::出発前の進行を作る();
    assert_eq!(進行.到達を判定して進めた進行を返す(&道順, 高い位置).到達済みの目的地数(), 0);
}
