//! 共通入力層とゲームロジック層の境界の型を所有する。デバイスの種類(キーボード・パッド)はこの型より手前で消えており、
//! ここから先はどの操作が押されているかだけが残る。
//! 参照: `_doc/計画/ユビキタス言語.md`「ゲームインテント」。

/// 共通入力層が1フレームぶんを確定して渡す、デバイスに依らない操作の入力。
///
/// 決定と取り消しとジャンプとカメラの系統の切替を「押した瞬間か」で持つのは、押しっぱなしの間ずっと決定が届くとメニューが1フレームで流れ、
/// ジャンプが届き続けると着地のたびに跳び直し、切替が届き続けると系統が描画ごとに入れ替わるためである。
/// 移動の4つと走るは押下が続く間ずっと意味を持つため、押しているかで持つ。
/// カメラの系統の切替はゲームの意図へ写されず、コンポジションルートのゲーム配線が描画機会ごとに消費する。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 確定済みの操作入力 {
    pub 前へ進む操作を押しているか: bool,
    pub 後ろへ下がる操作を押しているか: bool,
    pub 左へ寄る操作を押しているか: bool,
    pub 右へ寄る操作を押しているか: bool,
    pub 走る操作を押しているか: bool,
    pub 決定操作を押した瞬間か: bool,
    pub 取り消し操作を押した瞬間か: bool,
    pub ジャンプ操作を押した瞬間か: bool,
    pub カメラの系統を切り替える操作を押した瞬間か: bool,
}

impl 確定済みの操作入力 {
    /// 押した瞬間の操作(決定・取り消し・ジャンプ・カメラの系統の切替)だけを落とし、押下が続く操作はそのまま残した入力。
    ///
    /// 1描画で複数の固定刻みを進める実行が使う。押した瞬間の操作を全ての刻みへ同じ値で渡すと、
    /// 1回の押し下げが刻みの本数だけ発火する。
    pub fn 押した瞬間の操作を落とした入力(&self) -> Self {
        Self {
            決定操作を押した瞬間か: false,
            取り消し操作を押した瞬間か: false,
            ジャンプ操作を押した瞬間か: false,
            カメラの系統を切り替える操作を押した瞬間か: false,
            ..*self
        }
    }

    /// どの操作も押されていない入力。
    pub fn 無操作() -> Self {
        Self {
            前へ進む操作を押しているか: false,
            後ろへ下がる操作を押しているか: false,
            左へ寄る操作を押しているか: false,
            右へ寄る操作を押しているか: false,
            走る操作を押しているか: false,
            決定操作を押した瞬間か: false,
            取り消し操作を押した瞬間か: false,
            ジャンプ操作を押した瞬間か: false,
            カメラの系統を切り替える操作を押した瞬間か: false,
        }
    }
}
