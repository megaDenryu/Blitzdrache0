//! カメラの遮蔽と復帰: プレイヤー用カメラが世界の形をどれだけ避け、遮蔽が消えた後にどの速さで理想距離へ戻るかの規則。
//! 持つのは方針の定数(球の半径・復帰の速さ・目の高さ)だけであり、世界を尋ねる口は描画ごとに借りて使う。
//!
//! 手順は、注視点から理想視点へ向けて球を掃引し、触れたら理想距離に動けた割合を掛けた長さを表示距離の目標にし、
//! 下限で切り上げ、前の表示距離より短ければ即時にその値へ、長ければ復帰の速さに進めた時間を掛けた分だけ伸ばす。
//! 掃引の答えが評価できない領域を含む描画は、前の表示距離を保つ(未読込の中へ視点を出さない安全側)。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断10」

use blitz_math::{メートル, メートル毎秒, 大域メートル, 大域ワールド位置};

use crate::camera_occlusion_input::遮蔽の判定の入力;
use crate::display_distance_decision::表示距離の決定;
use crate::occlusion_verdict::遮蔽の判定;
use crate::sweep_completeness::掃引の完全性;
use crate::sweep_hit::掃引が最初に触れる面;
use crate::world_shape_port::世界の形を尋ねる口;

const 初版の球の半径メートル: f32 = 0.25;
const 初版の復帰の速さメートル毎秒: f32 = 8.0;
const 初版の目の高さメートル: f32 = 0.4;

pub struct カメラの遮蔽と復帰 {
    球の半径: メートル,       // 近クリップ面が壁の中へ入らないための、掃引する球の半径
    復帰の速さ: メートル毎秒, // 遮蔽が消えた後に表示距離が理想距離へ伸びる速さ
    目の高さ: メートル,       // 足元の位置から注視点までの高さ
}

impl カメラの遮蔽と復帰 {
    /// 初版の値(半径0.25メートル・毎秒8メートル・目の高さ0.4メートル)で作る。値は実機で調整する。
    pub fn 初版の値で生成する() -> Self {
        Self {
            球の半径: メートル::生成する(初版の球の半径メートル),
            復帰の速さ: メートル毎秒::生成する(初版の復帰の速さメートル毎秒),
            目の高さ: メートル::生成する(初版の目の高さメートル),
        }
    }

    /// 足元の位置に目の高さを足した、カメラが見つめる点。
    pub fn 注視点を足元から求める(&self, 足元: 大域ワールド位置) -> 大域ワールド位置 {
        足元.平行移動する(大域ワールド位置::生成する(
            大域メートル::生成する(0.0),
            大域メートル::生成する(f64::from(self.目の高さ.値())),
            大域メートル::生成する(0.0),
        ))
    }

    /// その描画の表示距離を決める。問い合わせの失敗は口のエラーのまま上へ返す。
    pub fn 表示距離を決める<口: 世界の形を尋ねる口>(
        &self,
        口: &mut 口,
        入力: 遮蔽の判定の入力,
    ) -> Result<表示距離の決定, 口::問い合わせエラー> {
        let 答え = 口.掃引した球が最初に触れる面を求める(入力.注視点, self.球の半径, self.注視点から理想視点への変位(入力))?;
        let 前 = 入力.前の表示距離.基準にする距離(入力.理想距離);
        if 答え.完全性() == 掃引の完全性::評価できない領域を含む {
            return Ok(表示距離の決定::生成する(
                短いほう(前, 入力.理想距離),
                遮蔽の判定::評価できず前の表示距離を保った,
            ));
        }
        let (遮蔽で許される距離, 判定) = match 答え.面() {
            掃引が最初に触れる面::何にも触れない => (入力.理想距離, 遮蔽の判定::遮られていない),
            掃引が最初に触れる面::触れる(接触) => (入力.理想距離 * 接触.動けた割合().値(), 遮蔽の判定::遮られている),
        };
        let 目標 = 長いほう(遮蔽で許される距離, 入力.表示距離の下限);
        // 縮む向きは即時であり、伸びる向きだけを復帰の速さで遅らせる。
        let 表示距離 = if 目標 <= 前 {
            目標
        } else {
            短いほう(目標, 前 + self.復帰の速さ * 入力.進めた時間)
        };
        Ok(表示距離の決定::生成する(表示距離, 判定))
    }

    // 注視点から理想視点への変位。理想距離はカメラが1000メートル以下に収めるため単精度へ必ず収まり、収まらないのはプログラムの誤りである。
    fn 注視点から理想視点への変位(&self, 入力: 遮蔽の判定の入力) -> blitz_math::変位<blitz_math::ワールド> {
        入力
            .理想視点
            .局所ワールド位置へ狭める(入力.注視点)
            .unwrap_or_else(|誤り| panic!("注視点から理想視点への変位が単精度で表せない(不変条件が破れている): {誤り}"))
            .原点からの変位()
    }
}

fn 短いほう(左: メートル, 右: メートル) -> メートル {
    if 左 <= 右 { 左 } else { 右 }
}

fn 長いほう(左: メートル, 右: メートル) -> メートル {
    if 左 >= 右 { 左 } else { 右 }
}
