//! 水平面の向きを長さ1の2成分で表す値を所有する。触れるのは東成分と南成分の対だけであり、その向きが何の向きか
//! (前へ進む向きなのか、右へ寄る向きなのか)を知らない。
//!
//! 成分の名前が東と南なのはワールド軸に合わせたためである。Xが東、Zが南である(`_doc/計画/ユビキタス言語.md`「太陽方向」)。
//!
//! 生成の入口を方位角だけに絞るのは、長さが1であることを正弦と余弦が保証するためである。2つの成分を外から受け取る形にすると、
//! 長さが1でない対を渡せてしまい、歩く速さが向きによって変わる。

use blitz_math::ラジアン;

/// 水平面の向きを表す長さ1のベクトル。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 水平面の単位ベクトル {
    東成分: f32,
    南成分: f32,
}

impl 水平面の単位ベクトル {
    /// 方位角が指す向きから生成する。0が北(南成分が負)、増えると西(東成分が負)へ回る。
    ///
    /// 正弦と余弦を取り出す唯一の場所であり、方位角の測り方の規約はここに閉じる。
    pub fn 方位角から生成する(角: ラジアン) -> Self {
        Self {
            東成分: -角.値().sin(),
            南成分: -角.値().cos(),
        }
    }

    pub fn 東成分(self) -> f32 {
        self.東成分
    }

    pub fn 南成分(self) -> f32 {
        self.南成分
    }

    /// 方位角を直角ぶん減らした向きを返す。成分の入れ替えと符号の反転だけで求めるため、方位角から生成し直した値と一致する。
    pub(crate) fn 方位角を直角ぶん減らした向きを返す(self) -> Self {
        Self {
            東成分: -self.南成分,
            南成分: self.東成分,
        }
    }
}
