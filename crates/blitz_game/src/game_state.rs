//! クソゲー1本目の状態一式と、1刻みぶんの更新の入口を所有する。更新は今の状態を読んで新しい状態を返すだけであり、
//! 描画にもコンポジションルートにも触れない。
//!
//! 1刻みは描画フレーム1回ぶんであり、その長さはコンポジションルートが決めて渡す。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断1」。

use blitz_math::{大域ワールド位置, 秒};

use crate::forward_azimuth::前へ進む向きの方位角;
use crate::game_intent::ゲームインテント;
use crate::player_move::移動後のプレイヤーの大域位置を求める;
use crate::progress_stage::ゲームの進行段階;
use crate::stage_transition::次の進行段階を決める;
use crate::tour_progress::場所巡りの進行;
use crate::tour_route::場所巡りの道順;

/// 場所を巡るゲームが1フレームごとに更新する状態一式。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 場所巡りのゲームの状態 {
    進行段階: ゲームの進行段階,
    場所巡り: 場所巡りの進行,
    プレイヤーの大域位置: 大域ワールド位置,
}

impl 場所巡りのゲームの状態 {
    pub fn 開始時の状態を作る(プレイヤーの出発地点の大域位置: 大域ワールド位置) -> Self {
        Self {
            進行段階: ゲームの進行段階::タイトル表示中,
            場所巡り: 場所巡りの進行::出発前の進行を作る(),
            プレイヤーの大域位置: プレイヤーの出発地点の大域位置,
        }
    }

    /// 固定刻み1つぶんだけ進めた状態を返す。
    ///
    /// 移動と到達判定を場所巡り中の段階だけで行うのは、タイトルと終了確認の裏で位置が動くと、
    /// メニューを開いている間に目的地へ着いてしまうためである。
    pub fn 一刻み進めた状態を返す(
        &self,
        道順: &場所巡りの道順,
        インテント: ゲームインテント,
        刻み: 秒,
        前へ進む向き: 前へ進む向きの方位角,
    ) -> Self {
        let 次の段階 = 次の進行段階を決める(self.進行段階, インテント);
        if 次の段階 != ゲームの進行段階::場所巡り中 {
            return Self {
                進行段階: 次の段階, ..*self
            };
        }
        let 移動後の大域位置 = 移動後のプレイヤーの大域位置を求める(self.プレイヤーの大域位置, インテント, 刻み, 前へ進む向き);
        Self {
            進行段階: 次の段階,
            場所巡り: self.場所巡り.到達を判定して進めた進行を返す(道順, 移動後の大域位置),
            プレイヤーの大域位置: 移動後の大域位置,
        }
    }

    pub fn 進行段階(&self) -> ゲームの進行段階 {
        self.進行段階
    }

    pub fn 場所巡り(&self) -> 場所巡りの進行 {
        self.場所巡り
    }

    pub fn プレイヤーの大域位置(&self) -> 大域ワールド位置 {
        self.プレイヤーの大域位置
    }

    pub fn 終了が決まったか(&self) -> bool {
        self.進行段階 == ゲームの進行段階::終了決定済み
    }
}
