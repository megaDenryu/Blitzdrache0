//! クソゲー1本目の状態一式と、1刻みぶんの更新の入口を所有する。更新は今の状態を読んで新しい状態を返すだけであり、
//! 描画にもコンポジションルートにも触れない。
//!
//! 1刻みは描画フレーム1回ぶんであり、その長さはコンポジションルートが決めて渡す。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断1」。

use blitz_math::{大域ワールド位置, 秒};

use crate::facing_azimuth::動く個体が向いている方位角;
use crate::forward_azimuth::前へ進む向きの方位角;
use crate::game_intent::ゲームインテント;
use crate::ground_height::足元の地面の高さ;
use crate::player_placement::プレイヤーの位置と向き;
use crate::progress_stage::ゲームの進行段階;
use crate::tour_progress::場所巡りの進行;
use crate::tour_route::場所巡りの道順;

/// 場所を巡るゲームが1フレームごとに更新する状態一式。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 場所巡りのゲームの状態 {
    進行段階: ゲームの進行段階,
    場所巡り: 場所巡りの進行,
    プレイヤー: プレイヤーの位置と向き,
}

impl 場所巡りのゲームの状態 {
    /// 出発時の向きを外から受け取るのは、それがキツネの絵がどちらを向いて焼かれているかで決まる値であり、ゲームの規則ではないためである。
    pub fn 開始時の状態を作る(出発地点: 大域ワールド位置, 出発時の向き: 動く個体が向いている方位角) -> Self {
        Self {
            進行段階: ゲームの進行段階::タイトル表示中,
            場所巡り: 場所巡りの進行::出発前の進行を作る(),
            プレイヤー: プレイヤーの位置と向き::生成する(出発地点, 出発時の向き),
        }
    }

    /// 固定刻み1つぶんだけ進めた状態を返す。
    ///
    /// 移動と到達判定を場所巡り中の段階だけで行うのは、タイトルと終了確認の裏で位置が動くと、
    /// メニューを開いている間に目的地へ着いてしまうためである。
    pub fn 一刻み進めた状態を返す(
        &self,
        道順: &場所巡りの道順,
        インテント: ゲームインテント,
        刻み: 秒,
        前へ進む向き: 前へ進む向きの方位角,
    ) -> Self {
        let 次の段階 = self.進行段階.次の段階を決める(インテント);
        if 次の段階 != ゲームの進行段階::場所巡り中 {
            return Self {
                進行段階: 次の段階, ..*self
            };
        }
        let 移動後 = self.プレイヤー.移動後の位置と向きを返す(インテント, 刻み, 前へ進む向き);
        Self {
            進行段階: 次の段階,
            場所巡り: self.場所巡り.到達を判定して進めた進行を返す(道順, 移動後.大域位置()),
            プレイヤー: 移動後,
        }
    }

    /// 足元の地面の高さをプレイヤーの大域位置の天頂成分へ反映した状態を返す。
    ///
    /// 高さが分からない2つの枝で天頂成分を動かさないのは、0メートルへ落とすと標高0の平地と区別できず、
    /// 高さ場を焼き忘れた世界でキツネが地面へ沈んでも絵から理由が読み取れなくなるためである。
    pub fn 足元の地面の高さを反映した状態を返す(&self, 地面の高さ: 足元の地面の高さ) -> Self {
        let 足元の地面の高さ::高さ場から参照した高さ(高さ) = 地面の高さ else {
            return *self;
        };
        Self {
            プレイヤー: self.プレイヤー.天頂成分を据えた位置と向きを返す(高さ),
            ..*self
        }
    }

    pub fn 進行段階(&self) -> ゲームの進行段階 {
        self.進行段階
    }

    pub fn 場所巡り(&self) -> 場所巡りの進行 {
        self.場所巡り
    }

    pub fn プレイヤーの大域位置(&self) -> 大域ワールド位置 {
        self.プレイヤー.大域位置()
    }

    pub fn プレイヤーの向き(&self) -> 動く個体が向いている方位角 {
        self.プレイヤー.向き()
    }

    pub fn 終了が決まったか(&self) -> bool {
        self.進行段階 == ゲームの進行段階::終了決定済み
    }
}
