//! クソゲー1本目の状態一式と、規則の各段の変換(進行段階の遷移・プレイヤーの移動・到達判定)を所有する。どの変換も今の状態を
//! 読んで新しい状態を返すだけであり、描画にもコンポジションルートにも触れない。世界の形を尋ねる口は刻みごとに借りて使う。
//!
//! 3つの変換をどの順で呼び、移動と到達判定をこの刻みに行うかは、固定刻みの工程(コンポジションルート)が
//! `ゲームの進行段階::移動と到達判定を行う段階か`を読んで決める。1刻みの長さもコンポジションルートが決めて渡す。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断1」「判断13」。

use blitz_design::{M不変データ, M射影関数, M状態};
use blitz_math::大域ワールド位置;

use crate::facing_azimuth::動く個体が向いている方位角;
use crate::game_intent::ゲームの操作意図;
use crate::ground_height::足元の地面の高さ;
use crate::movement::一刻みの移動の入力;
use crate::movement::移動の観測;
use crate::movement::移動状態;
use crate::player_state::プレイヤーの状態;
use crate::progress_stage::ゲームの進行段階;
use crate::tour_progress::場所巡りの進行;
use crate::tour_route::場所巡りの道順;
use crate::world_shape_port::世界の形を尋ねる口;

/// 場所を巡るゲームが1刻みごとに更新する状態一式。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 場所巡りのゲームの状態 {
    進行段階: ゲームの進行段階,
    場所巡り: 場所巡りの進行,
    プレイヤー: プレイヤーの状態,
}

impl M不変データ for 場所巡りのゲームの状態 {}
impl M状態 for 場所巡りのゲームの状態 {}

impl 場所巡りのゲームの状態 {
    /// 出発時の向きを外から受け取るのは、それがキツネの絵がどちらを向いて焼かれているかで決まる値であり、ゲームの規則ではないためである。
    pub fn 開始時の状態を作る(出発地点: 大域ワールド位置, 出発時の向き: 動く個体が向いている方位角) -> Self {
        Self {
            進行段階: ゲームの進行段階::タイトル表示中,
            場所巡り: 場所巡りの進行::出発前の進行を作る(),
            プレイヤー: プレイヤーの状態::開始時の状態を作る(出発地点, 出発時の向き),
        }
    }

    /// 操作の意図で進行段階を遷移させた状態を返す。触れるのは進行段階だけであり、プレイヤーと場所巡りの進行は動かさない。
    /// 固定刻みの工程の操作入力の適用と操作で決まる状態遷移の段が呼ぶ(参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」)。
    pub fn 操作の意図で進行段階を遷移させた状態を返す(&self, 意図: ゲームの操作意図) -> Self {
        Self {
            進行段階: self.進行段階.次の段階を決める(意図),
            ..*self
        }
    }

    /// プレイヤーを固定刻み1つぶん動かした状態と、その刻みの移動の観測を返す。進行段階を見ない。
    /// この刻みに動かすかどうかは、`ゲームの進行段階::移動と到達判定を行う段階か`を読んだ呼び出し側の決定である。
    pub fn プレイヤーを一刻み動かした状態と観測を返す<口: 世界の形を尋ねる口>(&self, 口: &mut 口, 入力: &一刻みの移動の入力) -> Result<(Self, 移動の観測), 口::問い合わせエラー> {
        let (移動後, 観測) = self.プレイヤー.一刻み動かした状態を返す(口, 入力)?;
        Ok((Self { プレイヤー: 移動後, ..*self }, 観測))
    }

    /// 今のプレイヤーの大域位置で目的地への到達を判定し、場所巡りの進行を進めた状態を返す。進行段階を見ない。
    pub fn 目的地への到達を判定して場所巡りの進行を進めた状態を返す(&self, 道順: &場所巡りの道順) -> Self {
        Self {
            場所巡り: self.場所巡り.到達を判定して進めた進行を返す(道順, self.プレイヤーの大域位置()),
            ..*self
        }
    }

    /// 足元の地面の高さをプレイヤーの大域位置の天頂成分へ据えた状態を返す。高さ場を据える起動時の据え直しだけが使い、
    /// 毎刻みの接地は掃引による接地判定が決める。
    ///
    /// 高さが分からない2つの選択肢で天頂成分を動かさないのは、0メートルへ落とすと標高0の平地と区別できず、
    /// 高さ場を焼き忘れた世界でキツネが地面へ沈んでも絵から理由が読み取れなくなるためである。
    pub fn 足元の地面の高さを反映した状態を返す(&self, 地面の高さ: 足元の地面の高さ) -> Self {
        let 足元の地面の高さ::高さ場から参照した高さ(高さ) = 地面の高さ else {
            return *self;
        };
        Self {
            プレイヤー: self.プレイヤー.天頂成分を据え直した状態を返す(高さ),
            ..*self
        }
    }

    pub fn 進行段階(&self) -> ゲームの進行段階 {
        self.進行段階
    }

    pub fn 場所巡り(&self) -> 場所巡りの進行 {
        self.場所巡り
    }

    pub fn プレイヤーの大域位置(&self) -> 大域ワールド位置 {
        self.プレイヤー.位置と向き().大域位置()
    }

    pub fn プレイヤーの向き(&self) -> 動く個体が向いている方位角 {
        self.プレイヤー.位置と向き().向き()
    }

    pub fn プレイヤーの移動状態(&self) -> 移動状態 {
        self.プレイヤー.移動状態()
    }

    pub fn 終了が決まったか(&self) -> bool {
        self.進行段階 == ゲームの進行段階::終了決定済み
    }
}

// 4つの取り出しが射影の役割(M状態 から M不変データ)を満たすことをコンパイラに確かめさせる。
const _: M射影関数<場所巡りのゲームの状態, 動く個体が向いている方位角> = M射影関数::生成する(場所巡りのゲームの状態::プレイヤーの向き);
const _: M射影関数<場所巡りのゲームの状態, ゲームの進行段階> = M射影関数::生成する(場所巡りのゲームの状態::進行段階);
const _: M射影関数<場所巡りのゲームの状態, 場所巡りの進行> = M射影関数::生成する(場所巡りのゲームの状態::場所巡り);
const _: M射影関数<場所巡りのゲームの状態, 移動状態> = M射影関数::生成する(場所巡りのゲームの状態::プレイヤーの移動状態);
