//! 前へ進む向きを変えたときに移動がどちらへ向くかの検査。反証したいのは、移動がワールド軸に固定されたままで
//! カメラの向きを変えても同じ方角へ歩いてしまうことである。姿勢の検査は`移動と向きの試験`にある。
//! 世界は床だけの世界であり、足元は床の上に据えてから動かす。

use blitz_math::{ラジアン, 大域メートル, 大域ワールド位置, 秒};

use crate::プレイヤー::プレイヤーの状態;
use crate::前へ進む向き::前へ進む向きの方位角;
use crate::向いている方位角::動く個体が向いている方位角;
use crate::操作意図::ゲームの操作意図;
use crate::操作意図の命令::胴体の移動の命令の組;
use crate::検査用の世界::平面と段と壁の世界;
use crate::確定済みの入力::{押した瞬間の操作の入力, 押下が続く操作の入力, 確定済みの操作入力};
use crate::移動::{胴体の移動, 胴体の移動の遷移パラメータ};

const 基本刻みの秒: f32 = 1.0 / 60.0;
/// 位置の比較に許す誤差。1刻みで進む距離が約0.067メートルであるため、この幅は向きの取り違えを見逃さない。
const 許す誤差メートル: f64 = 1.0e-6;

fn 前へ倒した意図() -> ゲームの操作意図 {
    ゲームの操作意図::確定済みの操作入力から写す(確定済みの操作入力::生成する(
        押下が続く操作の入力::無操作().前へ進む操作を押しているかを置き換えた入力(true),
        押した瞬間の操作の入力::無操作(),
    ))
}

fn 右へ倒した意図() -> ゲームの操作意図 {
    ゲームの操作意図::確定済みの操作入力から写す(確定済みの操作入力::生成する(
        押下が続く操作の入力::無操作().右へ寄る操作を押しているかを置き換えた入力(true),
        押した瞬間の操作の入力::無操作(),
    ))
}

fn 胴体の移動の命令の組で動かす(状態: プレイヤーの状態, 操作: 胴体の移動の命令の組, 入力: 胴体の移動の遷移パラメータ) -> プレイヤーの状態 {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0));
    match 状態.胴体の移動の命令の組で動かした状態を返す(&操作, &胴体の移動::初版の値で生成する(), 入力, &mut 世界) {
        Ok(成功) => 成功.次の状態,
        Err(失敗) => match 失敗.失敗の理由 {},
    }
}

// 原点の床の上に北を向いて立った状態から1刻み動かし、原点から見た足元の変位を返す。
pub(crate) fn 胴体の移動の命令の組で動かした位置(意図: ゲームの操作意図, 前へ進む向き: 前へ進む向きの方位角) -> 大域ワールド位置 {
    let 立った = 胴体の移動の命令の組で動かす(
        プレイヤーの状態::開始時の状態を作る(大域ワールド位置::原点(), 動く個体が向いている方位角::北を向く()),
        胴体の移動の命令の組::何もしない(),
        胴体の移動の遷移パラメータ::生成する(秒::生成する(基本刻みの秒), 前へ進む向き),
    );
    let 動いた = 胴体の移動の命令の組で動かす(立った, 意図.胴体の移動の命令の組(), 胴体の移動の遷移パラメータ::生成する(秒::生成する(基本刻みの秒), 前へ進む向き));
    動いた.位置と向き().大域位置().平行移動する(大域ワールド位置::生成する(
        大域メートル::生成する(-立った.位置と向き().大域位置().x().値()),
        大域メートル::生成する(-立った.位置と向き().大域位置().y().値()),
        大域メートル::生成する(-立った.位置と向き().大域位置().z().値()),
    ))
}

fn 西を指す向き() -> 前へ進む向きの方位角 {
    前へ進む向きの方位角::生成する(ラジアン::度から(90.0))
}

#[test]
fn 北を向いて前へ倒すと北へ動く() {
    let 位置 = 胴体の移動の命令の組で動かした位置(前へ倒した意図(), 前へ進む向きの方位角::北を指す());
    assert!(位置.z().値() < -許す誤差メートル);
    assert!(位置.x().値().abs() < 許す誤差メートル);
}

#[test]
fn 西を向いて前へ倒すと西へ動く() {
    let 位置 = 胴体の移動の命令の組で動かした位置(前へ倒した意図(), 西を指す向き());
    assert!(位置.x().値() < -許す誤差メートル);
    assert!(位置.z().値().abs() < 許す誤差メートル);
}

/// 前が西のとき右は北である。右へ倒したときに東へ動くなら、右の向きが前の向きに追従していない。
#[test]
fn 西を向いて右へ倒すと北へ動く() {
    let 位置 = 胴体の移動の命令の組で動かした位置(右へ倒した意図(), 西を指す向き());
    assert!(位置.z().値() < -許す誤差メートル);
    assert!(位置.x().値().abs() < 許す誤差メートル);
}

/// 反証: 斜めに倒したときの速さが軸1本より速いと、斜め移動が近道になる。
#[test]
fn 斜めに倒しても1つの刻みで進む距離が軸一本と変わらない() {
    let 斜め = ゲームの操作意図::確定済みの操作入力から写す(確定済みの操作入力::生成する(
        押下が続く操作の入力::無操作().前へ進む操作を押しているかを置き換えた入力(true).右へ寄る操作を押しているかを置き換えた入力(true),
        押した瞬間の操作の入力::無操作(),
    ));
    let 斜めの位置 = 胴体の移動の命令の組で動かした位置(斜め, 前へ進む向きの方位角::北を指す());
    let 軸一本の位置 = 胴体の移動の命令の組で動かした位置(前へ倒した意図(), 前へ進む向きの方位角::北を指す());
    let 斜めの距離 = (斜めの位置.x().値().powi(2) + 斜めの位置.z().値().powi(2)).sqrt();
    let 軸一本の距離 = (軸一本の位置.x().値().powi(2) + 軸一本の位置.z().値().powi(2)).sqrt();
    assert!((斜めの距離 - 軸一本の距離).abs() < 許す誤差メートル);
}
