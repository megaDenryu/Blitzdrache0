//! 遮蔽の判定の入力: 前の描画の表示距離の状態遷移が1描画に1度受け取る、状態でも規則でもない必須の入力の束(状態遷移パラメータ)。
//! 前の描画の表示距離を持たないのは、それが状態遷移の状態そのものであり、状態の位置で受け取るためである。
//!
//! 表示距離の下限を入力で受けるのは、その値がエンジンのオービットカメラの最小距離であり、ゲームロジック層が
//! 写しの定数を持つと2つ目の所有者になるためである。進めた時間は実時間でなく、その描画で進めた刻み数に基本刻みを掛けた値である。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断10」「判断12」

use blitz_design::{MParameter, M不変データ};
use blitz_math::{メートル, 大域ワールド位置, 秒};

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 遮蔽の判定の入力 {
    注視点: 大域ワールド位置,   // 混ぜた足元の位置に目の高さを足した点
    理想視点: 大域ワールド位置, // ヨー・ピッチ・理想距離が決める、遮蔽を考えない視点
    理想距離: メートル,         // 注視点から理想視点までの距離
    表示距離の下限: メートル,   // オービットカメラの最小距離
    進めた時間: 秒,             // その描画で進めた刻み数に基本刻みを掛けた時間
}

impl M不変データ for 遮蔽の判定の入力 {}
impl MParameter for 遮蔽の判定の入力 {}

impl 遮蔽の判定の入力 {
    pub fn 生成する(注視点: 大域ワールド位置, 理想視点: 大域ワールド位置, 理想距離: メートル, 表示距離の下限: メートル, 進めた時間: 秒) -> Self {
        Self {
            注視点,
            理想視点,
            理想距離,
            表示距離の下限,
            進めた時間,
        }
    }

    pub fn 注視点(&self) -> 大域ワールド位置 {
        self.注視点
    }

    pub fn 理想視点(&self) -> 大域ワールド位置 {
        self.理想視点
    }

    pub fn 理想距離(&self) -> メートル {
        self.理想距離
    }

    pub fn 表示距離の下限(&self) -> メートル {
        self.表示距離の下限
    }

    pub fn 進めた時間(&self) -> 秒 {
        self.進めた時間
    }
}
