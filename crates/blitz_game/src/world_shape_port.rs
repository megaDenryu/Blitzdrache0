//! 世界の形を尋ねる口: ゲームロジック層が自分の語彙で定めた、世界の形へ問いを渡して答えを受け取るトレイト。
//!
//! トレイトにするのは実装が2つあるためである。コンポジションルートのゲーム配線が持つ実装はエンジンの世界の形への
//! 問い合わせを包み、ゲームロジック層の検査が持つ実装は平面と段と壁だけの世界である。既存の高さ場の写しと同じ形であり、
//! 違いは「答えを写す」だけでなく「問いを渡す」向きが加わることである。
//!
//! 問い合わせが型付きエラーで失敗したら握り潰さず上へ返す。エラーの型を実装ごとに持たせるのは、エンジンの問い合わせが
//! 拒む理由をゲームロジック層が名指しできないためである。検査の世界は失敗しないため`Infallible`を置く。
//! `&mut self`で受けるのは、配線の実装が候補の受け皿を持って使い回すためである。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断3」

use blitz_math::{メートル, ワールド, 変位, 大域ワールド位置};

use crate::body_capsule::胴体カプセル;
use crate::sweep_answer::掃引の答え;

pub trait 世界の形を尋ねる口 {
    type 問い合わせエラー: std::error::Error;

    /// 胴体カプセルを掃引の変位だけ動かしたとき、最初に触れる面を求める。
    fn 掃引した胴体が最初に触れる面を求める(
        &mut self,
        胴体: 胴体カプセル,
        掃引の変位: 変位<ワールド>,
    ) -> Result<掃引の答え, Self::問い合わせエラー>;

    /// 中心と半径で決まる球を掃引の変位だけ動かしたとき、最初に触れる面を求める。軸の長さ0のカプセルである。
    fn 掃引した球が最初に触れる面を求める(
        &mut self,
        中心: 大域ワールド位置,
        半径: メートル,
        掃引の変位: 変位<ワールド>,
    ) -> Result<掃引の答え, Self::問い合わせエラー>;
}
