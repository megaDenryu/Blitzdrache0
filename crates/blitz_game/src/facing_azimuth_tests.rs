//! 向きを目標へ回す角の検査。反証したいのは、逆回りで遠回りすること、1刻みで目標へ飛んでしまうこと、
//! 回り過ぎて目標を通り越して振動することの3つである。

use blitz_math::{ラジアン, ラジアン毎秒, 秒};

use crate::facing_azimuth::動く個体が向いている方位角;

const 一刻み: f32 = 1.0 / 60.0;
/// 検査で使う回る速さ。毎秒60度は1刻みでちょうど1度回るため、回った角をそのまま読める。
const 回る速さの度毎秒: f32 = 60.0;
const 許す誤差度: f32 = 1.0e-3;

fn 度から作る(度: f32) -> 動く個体が向いている方位角 {
    動く個体が向いている方位角::生成する(ラジアン::度から(度))
}

fn 度で読む(向き: 動く個体が向いている方位角) -> f32 {
    向き.ラジアンで表した角().値().to_degrees()
}

fn 一刻み回す(
    今の向き: 動く個体が向いている方位角, 目標の向き: 動く個体が向いている方位角
) -> 動く個体が向いている方位角 {
    今の向き.目標の向きへ一刻みぶん回した向きを返す(目標の向き, ラジアン毎秒::度毎秒から(回る速さの度毎秒), 秒::生成する(一刻み))
}

#[test]
fn 目標が正の側にあるときは正の側へ回る() {
    let 結果 = 一刻み回す(度から作る(0.0), 度から作る(90.0));
    assert!((度で読む(結果) - 1.0).abs() < 許す誤差度);
}

/// 反証: 折り返さずに差を測ると、350度の位置から0度へ回るのに正の側へ350度回る。
#[test]
fn 一周をまたぐ差は短いほうへ回る() {
    let 結果 = 一刻み回す(度から作る(-170.0), 度から作る(170.0));
    assert!((度で読む(結果) + 171.0).abs() < 許す誤差度);
}

/// 目標までの残りが1刻みで回れる角より小さいときは、行き過ぎずに目標で止まる。
#[test]
fn 残りが一刻みより小さいと目標で止まる() {
    let 結果 = 一刻み回す(度から作る(0.0), 度から作る(0.4));
    assert!((度で読む(結果) - 0.4).abs() < 許す誤差度);
}

/// 反証: 半周の幅へ折り返さないと、同じ方向へ回り続けたときに角が際限なく増える。
#[test]
fn 回り続けても角は半周の幅に収まる() {
    let 目標 = 度から作る(180.0);
    let mut 向き = 度から作る(0.0);
    for _ in 0..400 {
        向き = 一刻み回す(向き, 目標);
    }
    assert!(度で読む(向き).abs() <= 180.0 + 許す誤差度);
}
