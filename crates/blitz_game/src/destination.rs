//! 場所巡りの1つの目的地を所有する。触れるのは大域位置と到達とみなす半径の2つだけであり、
//! その半径での到達判定もここに閉じる。

use blitz_math::{メートル, 大域ワールド位置};

/// 巡る先の1つ。到達とみなす半径を目的地ごとに持つのは、広場と細い道で近づける距離が違うためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 目的地 {
    大域位置: 大域ワールド位置,
    到達とみなす半径: メートル,
}

impl 目的地 {
    /// 注意: 到達とみなす半径は有限かつ0以上でなければならない。負や非数を渡すとどの位置でも到達が成立しなくなり、
    /// 場所巡りが1つも進まないまま止まる。到達したらバグである状態のためpanicで止める。
    pub fn 生成する(大域位置: 大域ワールド位置, 到達とみなす半径: メートル) -> Self {
        assert!(
            到達とみなす半径.値().is_finite() && 到達とみなす半径.値() >= 0.0,
            "目的地の到達とみなす半径は有限かつ0以上でなければならない: {}",
            到達とみなす半径.値()
        );
        Self {
            大域位置, 到達とみなす半径
        }
    }

    pub fn 大域位置(&self) -> 大域ワールド位置 {
        self.大域位置
    }

    pub fn 到達とみなす半径(&self) -> メートル {
        self.到達とみなす半径
    }

    /// 高さの差も距離に数える。橋の上と下を同じ地点として数えないためである。
    pub fn 到達したとみなせるか(&self, プレイヤーの大域位置: 大域ワールド位置) -> bool {
        let 東西の差 = プレイヤーの大域位置.x().値() - self.大域位置.x().値();
        let 高さの差 = プレイヤーの大域位置.y().値() - self.大域位置.y().値();
        let 南北の差 = プレイヤーの大域位置.z().値() - self.大域位置.z().値();
        let 距離の二乗 = 東西の差 * 東西の差 + 高さの差 * 高さの差 + 南北の差 * 南北の差;
        let 半径 = f64::from(self.到達とみなす半径.値());
        距離の二乗 <= 半径 * 半径
    }
}
