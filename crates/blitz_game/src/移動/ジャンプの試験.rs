//! 胴体の移動のジャンプの検査。接地中でジャンプの操作が届いた刻みに初速で空中へ移り、約0.8メートルまで上がって着地すること、
//! 空中ではジャンプの操作が無視されることを固定する(判断5)。世界と刻む手順の助けは`胴体の移動の試験の助け`にある。

use blitz_math::{メートル毎秒, 大域メートル};

use super::動き方::移動状態;
use super::胴体の移動の試験の助け;
use crate::操作意図::ゲームの操作意図;
use crate::検査用の世界::平面と段と壁の世界;
use crate::確定済みの入力::{押した瞬間の操作の入力, 押下が続く操作の入力, 確定済みの操作入力};

#[test]
fn ジャンプすると約0点8メートルまで上がって着地する() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0));
    let (足元, 状態) = 胴体の移動の試験の助け::床の上で接地した状態(&mut 世界, 0.0, 0.0, 0.0);
    let ジャンプ = ゲームの操作意図::確定済みの操作入力から写す(確定済みの操作入力::生成する(
        押下が続く操作の入力::無操作(),
        押した瞬間の操作の入力::無操作().ジャンプ操作を押した瞬間かを置き換えた入力(true),
    ));
    let (mut 足元, mut 状態, _, _) = 胴体の移動の試験の助け::同じ入力で刻む(&mut 世界, 足元, 状態, &胴体の移動の試験の助け::移動の入力(ジャンプ, 0.0), 1);
    assert!(matches!(状態, 移動状態::空中 { 速度 } if 速度.鉛直() > メートル毎秒::生成する(0.0)));
    let mut 最高点 = 足元.y().値();
    let mut 着地までの刻み = 0;
    while matches!(状態, 移動状態::空中 { .. }) && 着地までの刻み < 120 {
        (足元, 状態, _, _) = 胴体の移動の試験の助け::同じ入力で刻む(&mut 世界, 足元, 状態, &胴体の移動の試験の助け::移動の入力(ゲームの操作意図::無操作(), 0.0), 1);
        最高点 = 最高点.max(足元.y().値());
        着地までの刻み += 1;
    }
    assert!(matches!(状態, 移動状態::接地中 { .. }), "{着地までの刻み}刻みで着地しなかった");
    assert!((0.7..0.9).contains(&最高点), "最高点{最高点}");
}

// 反証: 空中でジャンプの操作を受け付けると、落下中に何度でもジャンプし直せる。
#[test]
fn 空中ではジャンプの操作が無視される() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0));
    let ジャンプ = ゲームの操作意図::確定済みの操作入力から写す(確定済みの操作入力::生成する(
        押下が続く操作の入力::無操作(),
        押した瞬間の操作の入力::無操作().ジャンプ操作を押した瞬間かを置き換えた入力(true),
    ));
    let (_, 状態, _, _) = 胴体の移動の試験の助け::同じ入力で刻む(
        &mut 世界,
        胴体の移動の試験の助け::大域位置(0.0, 5.0, 0.0),
        移動状態::開始時は空中で静止している(),
        &胴体の移動の試験の助け::移動の入力(ジャンプ, 0.0),
        1,
    );
    let 移動状態::空中 { 速度 } = 状態 else {
        panic!("5メートルの高さから始めた刻みが空中でない");
    };
    assert!(速度.鉛直() < メートル毎秒::生成する(0.0), "鉛直の速度{}", 速度.鉛直().値());
}
