//! 胴体の移動の検査が共有する助け。世界を組んで刻む手順と、床の上で接地した状態の作り方を持つ。
//! 検査そのものは`胴体の移動の試験`(平地・壁・崖・完全性)・`ジャンプの試験`(ジャンプ)・`斜面の試験`(斜面)にある。

use blitz_math::{ラジアン, 大域メートル, 大域ワールド位置, 秒};

use super::動き方::移動状態;
use super::移動の入力::胴体の移動の遷移パラメータ;
use super::胴体の移動の規則::胴体の移動;
use super::観測::移動の観測;
use crate::前へ進む向き::前へ進む向きの方位角;
use crate::操作意図::ゲームの操作意図;
use crate::操作意図の命令::胴体の移動の命令の組;
use crate::検査用の世界::平面と段と壁の世界;
use crate::確定済みの入力::{押した瞬間の操作の入力, 押下が続く操作の入力, 確定済みの操作入力};

pub(crate) const 基本刻みの秒: f32 = 1.0 / 60.0;

pub(crate) fn 大域位置(東: f64, 天頂: f64, 南: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(東), 大域メートル::生成する(天頂), 大域メートル::生成する(南))
}

pub(crate) fn 前へ倒した意図() -> ゲームの操作意図 {
    ゲームの操作意図::確定済みの操作入力から写す(確定済みの操作入力::生成する(
        押下が続く操作の入力::無操作().前へ進む操作を押しているかを置き換えた入力(true),
        押した瞬間の操作の入力::無操作(),
    ))
}

/// 検査が1刻みぶん与える、胴体の移動の命令の組(コマンドの位置で受け取る命令の組)と胴体の移動の遷移パラメータの組。
pub(crate) struct 検査の刻み {
    操作: 胴体の移動の命令の組,
    入力: 胴体の移動の遷移パラメータ,
}

pub(crate) fn 移動の入力(意図: ゲームの操作意図, 前へ進む向きの度: f32) -> 検査の刻み {
    検査の刻み {
        操作: 意図.胴体の移動の命令の組(),
        入力: 胴体の移動の遷移パラメータ::生成する(秒::生成する(基本刻みの秒), 前へ進む向きの方位角::生成する(ラジアン::度から(前へ進む向きの度))),
    }
}

impl 検査の刻み {
    // 同じ入力で回数だけ刻み、最後の足元・移動状態・観測と、途中で空中になった刻みがあったかを返す。
    pub(crate) fn 同じ入力で刻む(&self, 世界: &mut 平面と段と壁の世界, 足元: 大域ワールド位置, 状態: 移動状態, 回数: u32) -> (大域ワールド位置, 移動状態, 移動の観測, bool) {
        let 規則 = 胴体の移動::初版の値で生成する();
        let (mut 足元, mut 状態) = (足元, 状態);
        let mut 観測 = 移動の観測::移動を行わなかった刻み();
        let mut 空中を経た = false;
        for _ in 0..回数 {
            let 結果 = match 規則.足元と移動状態を動かす(世界, 足元, 状態, &self.操作, &self.入力) {
                Ok(結果) => 結果,
                Err(誤り) => match 誤り {},
            };
            足元 = 結果.足元();
            状態 = 結果.移動状態();
            観測 = 結果.観測();
            空中を経た |= matches!(状態, 移動状態::空中 { .. });
        }
        (足元, 状態, 観測, 空中を経た)
    }
}

// 床の面の高さに置いた足元を1刻み静止させ、接地判定が接地中と決めた足元と移動状態を返す。
pub(crate) fn 床の上で接地した状態(世界: &mut 平面と段と壁の世界, 東: f64, 床の高さ: f64, 南: f64) -> (大域ワールド位置, 移動状態) {
    let (足元, 状態, _, _) = 移動の入力(ゲームの操作意図::無操作(), 0.0).同じ入力で刻む(世界, 大域位置(東, 床の高さ, 南), 移動状態::開始時は空中で静止している(), 1);
    (足元, 状態)
}

// 2つの位置の水平(東と南)の隔たり。段差の持ち上げの検査が1刻みの水平移動を測る。
pub(crate) fn 水平の距離(左: 大域ワールド位置, 右: 大域ワールド位置) -> f64 {
    ((左.x().値() - 右.x().値()).powi(2) + (左.z().値() - 右.z().値()).powi(2)).sqrt()
}

// 2つの位置の成分ごとの差のうち最も大きい絶対値。静止や振動の検査が位置のずれを測る。
pub(crate) fn 最も離れた成分の差(左: 大域ワールド位置, 右: 大域ワールド位置) -> f64 {
    (左.x().値() - 右.x().値()).abs().max((左.y().値() - 右.y().値()).abs()).max((左.z().値() - 右.z().値()).abs())
}
