//! 胴体の移動の遷移パラメータ: 胴体の移動の遷移が1刻みに1度受け取る、状態でもコマンドでも規則でもない必須の入力の束(遷移パラメータ)。刻みの長さと前へ進む向きを持つ。
//! 命令の組(`胴体の移動の命令の組`)を持たないのは、命令の組を遷移の役割のコマンドの位置で受け取り、遷移パラメータへ混ぜないためである(設計オントロジー 3.5.1)。
//! 前へ進む向きを受け取るのは、その向きをカメラの方位から決めるのがコンポジションルートの配線であり、
//! ゲームロジック層がカメラの型を1つも知らないためである。

use blitz_design::{MParameter, M不変データ};
use blitz_math::秒;

use crate::前へ進む向き::前へ進む向きの方位角;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 胴体の移動の遷移パラメータ {
    刻み: 秒,
    前へ進む向き: 前へ進む向きの方位角,
}

impl M不変データ for 胴体の移動の遷移パラメータ {}
impl MParameter for 胴体の移動の遷移パラメータ {}

impl 胴体の移動の遷移パラメータ {
    pub fn 生成する(刻み: 秒, 前へ進む向き: 前へ進む向きの方位角) -> Self {
        Self { 刻み, 前へ進む向き }
    }

    pub fn 刻み(&self) -> 秒 {
        self.刻み
    }

    pub fn 前へ進む向き(&self) -> 前へ進む向きの方位角 {
        self.前へ進む向き
    }
}
