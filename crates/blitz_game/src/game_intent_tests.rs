//! 確定済みの操作入力からゲームの操作意図への写像と、命令ごとの解釈の検査。写像だけを対象にし、進行段階と位置には触れない。

use crate::confirmed_input::{押した瞬間の操作の入力, 押下が続く操作の入力, 確定済みの操作入力};
use crate::game_intent::ゲームの操作意図;
use crate::operation_axis::操作軸の倒し量;
use crate::操作意図の命令::{ジャンプの操作, 両軸の倒し量, 水平移動の操作, 進行の操作};

fn 倒し量(前後: f32, 左右: f32) -> 両軸の倒し量 {
    let 軸 = |値: f32| 操作軸の倒し量::押下の対から生成する(値 > 0.0, 値 < 0.0);
    両軸の倒し量::生成する(軸(前後), 軸(左右))
}

#[test]
fn 無操作の入力は無操作の意図へ写る() {
    let 意図 = ゲームの操作意図::確定済みの操作入力から写す(確定済みの操作入力::無操作());
    assert_eq!(意図, ゲームの操作意図::無操作());
}

#[test]
fn 前へ進む操作は前後の倒し量の正へ写り歩く() {
    let 入力 = 確定済みの操作入力::生成する(押下が続く操作の入力::無操作().前へ進む操作を押しているかを置き換えた入力(true), 押した瞬間の操作の入力::無操作());
    let 意図 = ゲームの操作意図::確定済みの操作入力から写す(入力);
    assert_eq!(意図.水平移動の操作(), 水平移動の操作::歩く(倒し量(1.0, 0.0)));
}

#[test]
fn 右へ寄る操作は左右の倒し量の正へ写る() {
    let 入力 = 確定済みの操作入力::生成する(押下が続く操作の入力::無操作().右へ寄る操作を押しているかを置き換えた入力(true), 押した瞬間の操作の入力::無操作());
    let 意図 = ゲームの操作意図::確定済みの操作入力から写す(入力);
    assert_eq!(意図.水平移動の操作().両軸の倒し量().左右の倒し量().値(), 1.0);
}

#[test]
fn 左へ寄る操作は左右の倒し量の負へ写る() {
    let 入力 = 確定済みの操作入力::生成する(押下が続く操作の入力::無操作().左へ寄る操作を押しているかを置き換えた入力(true), 押した瞬間の操作の入力::無操作());
    let 意図 = ゲームの操作意図::確定済みの操作入力から写す(入力);
    assert_eq!(意図.水平移動の操作().両軸の倒し量().左右の倒し量().値(), -1.0);
}

/// 反証: 前後を同時に押した入力が「前へ進む」として通ると、両押しで勝手に前進する。
#[test]
fn 前と後ろの同時押しは中立へ写り止まる() {
    let 入力 = 確定済みの操作入力::生成する(
        押下が続く操作の入力::無操作().前へ進む操作を押しているかを置き換えた入力(true).後ろへ下がる操作を押しているかを置き換えた入力(true),
        押した瞬間の操作の入力::無操作(),
    );
    let 意図 = ゲームの操作意図::確定済みの操作入力から写す(入力);
    assert_eq!(意図.水平移動の操作(), 水平移動の操作::止まる);
}

/// 反証: 決定とキャンセルを同時に押した刻みが決定へ解釈されると、終了確認でキャンセルしたはずの操作でゲームが閉じる。
#[test]
fn 決定とキャンセルの瞬間が同時ならキャンセルするへ解釈される() {
    let 入力 = 確定済みの操作入力::生成する(
        押下が続く操作の入力::無操作(),
        押した瞬間の操作の入力::無操作().決定操作を押した瞬間かを置き換えた入力(true).キャンセル操作を押した瞬間かを置き換えた入力(true),
    );
    assert_eq!(ゲームの操作意図::確定済みの操作入力から写す(入力).進行の操作(), 進行の操作::キャンセルする);
}

#[test]
fn 決定の瞬間だけなら決定するへ解釈される() {
    let 入力 = 確定済みの操作入力::生成する(押下が続く操作の入力::無操作(), 押した瞬間の操作の入力::無操作().決定操作を押した瞬間かを置き換えた入力(true));
    assert_eq!(ゲームの操作意図::確定済みの操作入力から写す(入力).進行の操作(), 進行の操作::決定する);
}

/// 反証: 倒していない刻みの走る操作が走るへ解釈されると、止まっているはずの胴体に走る速さが掛かる向きが生まれうる。
#[test]
fn 倒さずに走る操作を押すと止まるへ解釈される() {
    let 入力 = 確定済みの操作入力::生成する(押下が続く操作の入力::無操作().走る操作を押しているかを置き換えた入力(true), 押した瞬間の操作の入力::無操作());
    assert_eq!(ゲームの操作意図::確定済みの操作入力から写す(入力).水平移動の操作(), 水平移動の操作::止まる);
}

#[test]
fn 倒して走る操作を押すと走るへ解釈される() {
    let 入力 = 確定済みの操作入力::生成する(
        押下が続く操作の入力::無操作().前へ進む操作を押しているかを置き換えた入力(true).走る操作を押しているかを置き換えた入力(true),
        押した瞬間の操作の入力::無操作(),
    );
    let 水平移動 = ゲームの操作意図::確定済みの操作入力から写す(入力).水平移動の操作();
    assert_eq!(水平移動, 水平移動の操作::走る(倒し量(1.0, 0.0)));
    assert!(水平移動.走るか());
}

