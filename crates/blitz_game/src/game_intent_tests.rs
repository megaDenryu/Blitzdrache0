fn ジャンプの瞬間はジャンプするへ解釈される() {
    let 入力 = 確定済みの操作入力::生成する(押下が続く操作の入力::無操作(), 押した瞬間の操作の入力::無操作().ジャンプ操作を押した瞬間かを置き換えた入力(true));
    assert_eq!(ゲームの操作意図::確定済みの操作入力から写す(入力).ジャンプの操作(), ジャンプの操作::ジャンプする);
}

// 反証: 押した瞬間の操作を落とした入力にジャンプが残ると、1回の押し下げが刻みの本数だけジャンプする。
#[test]
fn 押した瞬間の操作を落とした入力はジャンプを落とし走るを残す() {
    let 入力 = 確定済みの操作入力::生成する(
        押下が続く操作の入力::無操作().走る操作を押しているかを置き換えた入力(true),
        押した瞬間の操作の入力::無操作().ジャンプ操作を押した瞬間かを置き換えた入力(true),
    )
    .押した瞬間の操作を落とした入力();
    assert!(!入力.押した瞬間の操作().ジャンプ操作を押した瞬間か());
    assert!(入力.押下が続く操作().走る操作を押しているか());
}
