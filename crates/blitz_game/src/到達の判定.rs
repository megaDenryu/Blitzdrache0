//! 目的地への到達の判定が、道順(規則)のほかに受け取る状態遷移パラメータ。今のプレイヤーの大域位置だけを持つ。
//!
//! プレイヤーの位置を道順と別の状態遷移パラメータにするのは、道順が場所巡りの間変わらない規則であるのに対し、位置は刻みごとに変わる必須の入力だからである。
//! 位置を裸の `大域ワールド位置` で受けないのは、`MParameter` を名乗る型として状態遷移の役割の宣言(`M規則と状態遷移パラメータで決まる状態遷移関数`)の型引数へ入れるためである。

use blitz_design::{MParameter, M不変データ};
use blitz_math::大域ワールド位置;

/// 目的地への到達の判定が受け取る状態遷移パラメータ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 到達の判定の状態遷移パラメータ {
    プレイヤーの大域位置: 大域ワールド位置,
}

impl M不変データ for 到達の判定の状態遷移パラメータ {}
impl MParameter for 到達の判定の状態遷移パラメータ {}

impl 到達の判定の状態遷移パラメータ {
    /// 今のプレイヤーの大域位置から組む。
    pub fn 生成する(プレイヤーの大域位置: 大域ワールド位置) -> Self {
        Self { プレイヤーの大域位置 }
    }

    /// 到達を判定するときのプレイヤーの大域位置。
    pub fn プレイヤーの大域位置(&self) -> 大域ワールド位置 {
        self.プレイヤーの大域位置
    }
}
