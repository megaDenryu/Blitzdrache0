//! 移動の1つの軸をどれだけ倒しているかを表す値を所有する。触れるのは倒し量そのものだけであり、
//! -1以上1以下という不変条件と、押下の対からの組み立てがこのファイルに閉じる。

/// 移動の1つの軸の倒し量。-1以上1以下の無次元の量であり、0が中立である。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 操作軸の倒し量(f32);

impl 操作軸の倒し量 {
    /// どちらの向きへも倒していない状態。
    pub fn 中立() -> Self {
        Self(0.0)
    }

    /// 正の向きと負の向きの押下の対から組み立てる。両方を同時に押している間は打ち消し合って中立になる。
    /// キーボードは倒し具合を持たないため、この組み立てが返すのは-1・0・1の3つだけである。
    pub fn 押下の対から生成する(正の向きを押しているか: bool, 負の向きを押しているか: bool) -> Self {
        match (正の向きを押しているか, 負の向きを押しているか) {
            (true, false) => Self(1.0),
            (false, true) => Self(-1.0),
            _ => Self(0.0),
        }
    }

    /// 移動量の計算へ渡すための取り出し。
    pub fn 値(self) -> f32 {
        self.0
    }
}
