#[test]
fn 段の上面は東端より東でだけ触れる() {
    let mut 世界 =
        平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0)).段を置く(大域メートル::生成する(5.0), 大域メートル::生成する(2.0));
    let 東端より西 = 世界
        .掃引した球が最初に触れる面を求める(大域位置(2.0, 4.0, 0.0), メートル::生成する(0.5), 変位(0.0, -4.0, 0.0))
        .unwrap();
    assert_eq!(触れた接触を取り出す(東端より西.面()).動けた割合().値(), 0.875);
    let 東端より東 = 世界
        .掃引した球が最初に触れる面を求める(大域位置(8.0, 4.0, 0.0), メートル::生成する(0.5), 変位(0.0, -4.0, 0.0))
        .unwrap();
    assert_eq!(触れた接触を取り出す(東端より東.面()).動けた割合().値(), 0.375);
}

#[test]
fn 段の蹴上げは上面より低い高さでだけ触れる() {
    let mut 世界 =
        平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0)).段を置く(大域メートル::生成する(5.0), 大域メートル::生成する(2.0));
    let 低い球 = 世界
        .掃引した球が最初に触れる面を求める(大域位置(2.0, 1.0, 0.0), メートル::生成する(0.5), 変位(4.0, 0.0, 0.0))
        .unwrap();
    assert_eq!(触れた接触を取り出す(低い球.面()).接触の単位法線().x(), -1.0);
    let 高い球 = 世界
        .掃引した球が最初に触れる面を求める(大域位置(2.0, 3.0, 0.0), メートル::生成する(0.5), 変位(4.0, 0.0, 0.0))
        .unwrap();
    assert_eq!(高い球.面(), 掃引が最初に触れる面::何にも触れない);
}

/// 反証: 評価できない領域を完全性で表さず「何にも触れない」を確定として返すと、未読込の中へ視点や胴体が入る。
#[test]
fn 評価できない領域へ達する掃引は完全性を落として何にも触れない() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0)).評価できない領域を東に置く(大域メートル::生成する(8.0));
    let 答え = 世界
        .掃引した球が最初に触れる面を求める(大域位置(8.0, 2.0, 0.0), メートル::生成する(0.5), 変位(0.0, -3.0, 0.0))
        .unwrap();
    assert_eq!(答え.面(), 掃引が最初に触れる面::何にも触れない);
    assert_eq!(答え.完全性(), 掃引の完全性::評価できない領域を含む);
}

#[test]
fn 胴体を下へ掃引すると軸の下端の半球が床に触れる() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0));
    let 胴体 = 胴体カプセル::初版の寸法で足元へ立てる(大域位置(0.0, 1.0, 0.0));
    let 答え = 世界.掃引した胴体が最初に触れる面を求める(胴体, 変位(0.0, -2.0, 0.0)).unwrap();
    let 接触 = 触れた接触を取り出す(答え.面());
    assert_eq!(接触.動けた割合().値(), 0.5);
    assert_eq!(接触.接触の大域位置().y(), 大域メートル::生成する(0.0));
}
