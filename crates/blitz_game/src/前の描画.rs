//! 前の描画の表示距離: 復帰の速さを効かせる基準と、評価できない描画で保つ値を運ぶ選択肢。表示距離と一緒に、
//! それを決めたときの理想距離を持つ。
//!
//! まだ1度も描いていない状態を選択肢で持つのは、最初の描画に基準が無いことを距離の値に密輸しないためである。
//! 最初の描画は理想距離を基準にし、遮られていればそこから即時に縮む。
//!
//! 基準に理想距離の増えたぶんを足すのは、利用者のズームアウト(理想距離の増加)を即時に通し、遮蔽からの回復だけを
//! 復帰の速さで遅らせるためである。前の表示距離をそのまま基準にすると、遮蔽が無くてもズームアウトが復帰の速さで遅れる。
//! 減ったぶんを基準から引かないのは、遮蔽で縮んでいる間のズームインで基準が遮蔽の許す距離より縮み、そこから復帰の速さで戻る揺れを作らないためである。
//! ズームインの即時性は、基準を今の理想距離で切り詰めることと、目標が基準以下なら即時に目標へ縮むことで守られる。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断10」「進行の記録」2026-09-02のレビュー是正

use blitz_design::{M不変データ, M状態, M規則で決まる問い合わせを伴う状態遷移関数, 問い合わせを伴う状態遷移の結果, 問い合わせを伴う状態遷移成功結果, 状態遷移失敗結果};
use blitz_math::メートル;

use crate::世界の形::{世界の形を尋ねる口, 口の実装が決める失敗の代表, 口の実装を代表する口};
use crate::表示距離::表示距離の決定;
use crate::遮蔽と復帰::カメラの遮蔽と復帰;
use crate::遮蔽の入力::遮蔽の判定の入力;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 前の描画の表示距離 {
    まだ描いていない,
    描いた { 表示距離: メートル, 理想距離: メートル },
}

impl M不変データ for 前の描画の表示距離 {}
impl M状態 for 前の描画の表示距離 {}

impl 前の描画の表示距離 {
    /// この描画の遮蔽を判定して表示距離を決め、その表示距離とこの描画の理想距離を持つ次の状態と、決めた表示距離と判定(観測)を返す。
    /// 問い合わせが失敗したら、受け取った状態を書き換えずに口の失敗と一緒に返す。
    pub fn 遮蔽を判定して次の描画の表示距離へ進める<口: 世界の形を尋ねる口 + ?Sized>(
        self,
        規則: &カメラの遮蔽と復帰,
        入力: 遮蔽の判定の入力,
        口: &mut 口,
    ) -> 問い合わせを伴う状態遷移の結果<Self, 表示距離の決定, 口::問い合わせエラー> {
        match 規則.表示距離を決める(self, 入力, 口) {
            Ok(決定) => Ok(問い合わせを伴う状態遷移成功結果::生成する(
                Self::描いた {
                    表示距離: 決定.表示距離(),
                    理想距離: 入力.理想距離(),
                },
                決定,
            )),
            Err(失敗の理由) => Err(状態遷移失敗結果::生成する(self, 失敗の理由)),
        }
    }

    /// 評価できない描画で保つ距離。前の表示距離を伸ばさず、今の理想距離で切り詰めるだけにする。
    /// 理想距離の増えたぶんを足さないのは、掃引が不完全なとき前の表示距離より先に未読込や壁が無いと確かめられないためである。
    /// まだ描いていなければ今の理想距離になる。
    pub(crate) fn 評価できない描画で保つ距離(self, 今の理想距離: メートル) -> メートル {
        match self {
            Self::まだ描いていない => 今の理想距離,
            Self::描いた { 表示距離, .. } => {
                if 表示距離 > 今の理想距離 {
                    今の理想距離
                } else {
                    表示距離
                }
            }
        }
    }

    /// 復帰と保持の基準にする距離。前の表示距離に理想距離の増えたぶんを足し、表示距離の下限で切り上げてから今の理想距離で切り詰める。
    /// まだ描いていなければ今の理想距離を基準にする。
    pub(crate) fn 基準にする距離(self, 今の理想距離: メートル, 表示距離の下限: メートル) -> メートル {
        match self {
            Self::まだ描いていない => 今の理想距離,
            Self::描いた { 表示距離, 理想距離 } => {
                let 変化を足した距離 = if 今の理想距離 > 理想距離 { 表示距離 + (今の理想距離 - 理想距離) } else { 表示距離 };
                let 下限で切り上げた距離 = if 変化を足した距離 < 表示距離の下限 { 表示距離の下限 } else { 変化を足した距離 };
                if 下限で切り上げた距離 > 今の理想距離 { 今の理想距離 } else { 下限で切り上げた距離 }
            }
        }
    }
}

// 遮蔽を判定して次の描画の表示距離へ進める が、コマンドを受けない問い合わせを伴う状態遷移の役割を満たすことをコンパイラに確かめさせる。
// 問い合わせ先と失敗は代表で具体化し、実際の失敗は口の実装が決める。
const _: M規則で決まる問い合わせを伴う状態遷移関数<前の描画の表示距離, カメラの遮蔽と復帰, 遮蔽の判定の入力, 口の実装を代表する口, 表示距離の決定, 口の実装が決める失敗の代表> =
    M規則で決まる問い合わせを伴う状態遷移関数::生成する(前の描画の表示距離::遮蔽を判定して次の描画の表示距離へ進める);
