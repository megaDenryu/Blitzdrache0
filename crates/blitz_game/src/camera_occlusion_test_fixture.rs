//! カメラの遮蔽と復帰の検査が共有する構図。注視点を東0メートル・天頂1メートル・南0メートルに置き、理想視点を真南へ
//! 理想距離だけ離した位置に置く。壁を南4メートルに置くと、半径0.25メートルの球は南3.75メートルで触れるため、
//! 理想距離8メートルなら動けた割合は0.46875である。

use blitz_math::{メートル, 大域メートル, 大域ワールド位置, 秒};

use crate::camera_occlusion::カメラの遮蔽と復帰;
use crate::camera_occlusion_input::遮蔽の判定の入力;
use crate::occlusion_verdict::遮蔽の判定;
use crate::planar_test_world::平面と段と壁の世界;
use crate::previous_display_distance::前の描画の表示距離;

pub(crate) const 一刻み: f32 = 1.0 / 60.0;

fn 注視点() -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(1.0), 大域メートル::生成する(0.0))
}

fn 真南の理想視点(理想距離: f32) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(0.0),
        大域メートル::生成する(1.0),
        大域メートル::生成する(f64::from(理想距離)),
    )
}

pub(crate) fn 入力(理想距離: f32, 前の表示距離: 前の描画の表示距離) -> 遮蔽の判定の入力 {
    遮蔽の判定の入力 {
        注視点: 注視点(),
        理想視点: 真南の理想視点(理想距離),
        理想距離: メートル::生成する(理想距離),
        表示距離の下限: メートル::生成する(0.5),
        前の表示距離,
        進めた時間: 秒::生成する(一刻み),
    }
}

pub(crate) fn 描いた(表示距離: f32, 理想距離: f32) -> 前の描画の表示距離 {
    前の描画の表示距離::描いた {
        表示距離: メートル::生成する(表示距離),
        理想距離: メートル::生成する(理想距離),
    }
}

pub(crate) fn 壁の無い世界() -> 平面と段と壁の世界 {
    平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0))
}

pub(crate) fn 南4メートルに壁のある世界() -> 平面と段と壁の世界 {
    壁の無い世界().壁を置く(大域メートル::生成する(4.0))
}

pub(crate) fn 決める(世界: &mut 平面と段と壁の世界, 入力: 遮蔽の判定の入力) -> (メートル, 遮蔽の判定) {
    match カメラの遮蔽と復帰::初版の値で生成する().表示距離を決める(世界, 入力) {
        Ok(決定) => (決定.表示距離(), 決定.判定()),
        Err(誤り) => match 誤り {},
    }
}
