//! 望みの動きの算出: 1刻みの移動の手順1。移動状態と操作の意図から、この刻みの速度と望みの変位と、
//! 刻みの終わりに接地判定を行うかを決める。掃引と滑りの反復へ渡す入力を組む工程であり、世界の形は尋ねない。
//!
//! 接地中は歩く速さか走る速さの水平の変位を接地面へ沿わせる(法線成分を除いて長さを保つ)。空中は前の刻みの速度を保ち、
//! 操作でその半分の速さまで水平を足し、鉛直は重力で進める。ジャンプは接地中でジャンプの操作が届いた刻みに初速を入れて
//! 空中へ移し、その刻みは接地判定を行わない(着地は次の刻み以降の接地判定が検出する)。上昇中(鉛直の速度が正)の刻みも
//! 接地判定を行わないのは、面から離れて行く途中で足元の下の面を拾い、飛び上がった直後に着地させないためである。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断5」「判断6」

use blitz_math::{メートル毎秒, ワールド, 変位};

use super::body_motion::胴体の移動;
use super::body_velocity::胴体の速度;
use super::movement_input::一刻みの移動の入力;
use super::movement_state::移動状態;
use super::stick_vector::世界の軸で見た倒し量;

/// この刻みに掃引する動き。
pub(crate) struct 望みの動き {
    pub(crate) 速度: 胴体の速度,
    pub(crate) 変位: 変位<ワールド>,
    pub(crate) 接地判定を行うか: bool,
}

impl 胴体の移動 {
    pub(crate) fn 望みの動きを求める(&self, 状態: 移動状態, 入力: &一刻みの移動の入力) -> 望みの動き {
        let 倒し = 世界の軸で見た倒し量::生成する(入力.インテント, 入力.前へ進む向き);
        match 状態 {
            移動状態::接地中 { 接地面の単位法線 } => {
                let 水平 = 倒し.速さを掛ける(self.速さ().接地中の速さ(入力.インテント.走りたいか));
                if 入力.インテント.ジャンプしたいか {
                    let 速度 = 胴体の速度::生成する(水平, self.落下とジャンプ().ジャンプの初速());
                    return 望みの動き {
                        速度,
                        変位: 速度.刻みぶんの変位を求める(入力.刻み),
                        接地判定を行うか: false,
                    };
                }
                let 速度 = 胴体の速度::水平だけ(水平);
                let 水平の変位 = 速度.刻みぶんの変位を求める(入力.刻み);
                望みの動き {
                    速度,
                    変位: 水平の変位.方向の成分を除く(接地面の単位法線).長さを付け替える(水平の変位.長さ()),
                    接地判定を行うか: true,
                }
            }
            移動状態::空中 { 速度 } => {
                let 落とした速度 = 速度.重力で落とす(self.落下とジャンプ().重力の加速度(), 入力.刻み, self.落下とジャンプ().落下の速さの上限());
                let 操作の変位 = 倒し
                    .速さを掛ける(self.速さ().空中で操作が変えられる速さ())
                    .刻みぶんの変位を求める(入力.刻み);
                望みの動き {
                    速度: 落とした速度,
                    変位: 落とした速度.刻みぶんの変位を求める(入力.刻み) + 操作の変位,
                    接地判定を行うか: 落とした速度.鉛直() <= メートル毎秒::生成する(0.0),
                }
            }
        }
    }
}
