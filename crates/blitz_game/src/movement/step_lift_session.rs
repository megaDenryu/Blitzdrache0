//! 段差の持ち上げ: 壁のような面の手前で止まった足元から、上へ段差の上限だけ掃引し、そこから前へ掃引し、持ち上げた分だけ
//! 下へ掃引する3件の掃引の途中状態を持つセッション型。始める口が作り、3件を終えると答えを返して閉じる。
//!
//! 上へ掃引して天井に触れたら、触れた高さまでで持ち上げる(それでも前へ進めるなら採る)。一歩も持ち上がらない刻みと、
//! 前へ一歩も進めない刻みは捨てる(前へ進めないなら段ではなく壁である)。下へ掃引した先が歩ける斜面の面なら、接地判定と
//! 同じ据え方(接触の位置から組んだ足元を鉛直に余白のぶん持ち上げる)でその位置を採り、触れなかったか歩けない面なら捨てる。
//!
//! 前へ掃引する長さは、残りの変位の長さと「段差の縁に立つのに要る前進」の長いほうである。軸の下端が球であるため、段の縁の上に
//! 歩ける面として立てるのは軸が縁から水平に半径×sin(歩ける斜面の限界)以内にあるときだけであり、縁へ最初に触れた位置から
//! それまでに要る前進は半径×(1−sin(限界))(初版の値で0.073メートル)である。歩く速さの1刻みの変位(0.067メートル)はこれに
//! 届かないため、残りの変位だけで前へ掃引すると下へ掃引した先が常に縁の急な部分になり、歩いて段を越えられない。判断7の
//! 「残りの変位で前へ掃引する」はこの下限つきで読む。下限が効く刻みの余分な前進は初版の値で最大0.012メートルであり、段を越える
//! 刻みだけに起きる。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断7」

use blitz_math::{メートル, ワールド, 変位, 大域ワールド位置, 方向, 符号付きの座標軸};

use super::downward_probe::下へ探った答え;
use super::ground_probe::接地の規則;
use super::query_count::問い合わせ件数;
use super::step_lift::持ち上げの答え;
use crate::body_capsule::胴体カプセル;
use crate::sweep_completeness::掃引の完全性;
use crate::sweep_hit::掃引が最初に触れる面;
use crate::world_shape_port::世界の形を尋ねる口;

#[must_use]
pub(crate) struct 段差の持ち上げ {
    足元: 大域ワールド位置,
    残りの変位: 変位<ワールド>,
    件数: 問い合わせ件数,
    段差の上限: メートル,
    接地: 接地の規則,
}

enum 掃引の続き {
    続ける { 進んだ割合: f32 },
    打ち切る(持ち上げの答え),
}

impl 段差の持ち上げ {
    pub(crate) fn 始める(
        足元: 大域ワールド位置,
        残りの変位: 変位<ワールド>,
        件数: 問い合わせ件数,
        段差の上限: メートル,
        接地: 接地の規則,
    ) -> Self {
        Self {
            足元,
            残りの変位,
            件数,
            段差の上限,
            接地,
        }
    }

    pub(crate) fn 上へ前へ下へ掃引する<口: 世界の形を尋ねる口>(
        mut self,
        口: &mut 口,
    ) -> Result<持ち上げの答え, 口::問い合わせエラー> {
        let 上へ = 変位::方向へ進む(方向::符号付きの座標軸から生成する(符号付きの座標軸::第二軸の正), self.段差の上限);
        let 持ち上げた長さ = match self.余白を残して進める(口, 上へ)? {
            掃引の続き::打ち切る(答え) => return Ok(答え),
            掃引の続き::続ける { 進んだ割合 } => self.段差の上限 * 進んだ割合,
        };
        let 半径 = 胴体カプセル::初版の寸法で足元へ立てる(self.足元).半径();
        let 下限 = self.接地.段差の縁に立つのに要る前進を求める(半径);
        let 残り = self.残りの変位.長さ();
        let 前へ = self.残りの変位.長さを付け替える(if 残り < 下限 { 下限 } else { 残り });
        if let 掃引の続き::打ち切る(答え) = self.余白を残して進める(口, 前へ)? {
            return Ok(答え);
        }
        self.下へ掃引する(口, 持ち上げた長さ)
    }

    // 変位で掃引し、触れたら余白を残すところまで動く。接触余白以下しか動けない(壁の手前で止まったままか、天井が頭の上にある)
    // 刻みは一歩も動けないとみなして捨てる。余白を残して止まる割合は単精度の丸めで零の代わりに極小の正を返すことがあり、
    // 零との比較では壁を押す刻みが前へ進めたことになって下への掃引まで数える。
    fn 余白を残して進める<口: 世界の形を尋ねる口>(
        &mut self,
        口: &mut 口,
        変位: 変位<ワールド>,
    ) -> Result<掃引の続き, 口::問い合わせエラー> {
        let 答え = 口.掃引した胴体が最初に触れる面を求める(胴体カプセル::初版の寸法で足元へ立てる(self.足元), 変位)?;
        self.件数 = self.件数.一件数える();
        if 答え.完全性() == 掃引の完全性::評価できない領域を含む {
            return Ok(掃引の続き::打ち切る(持ち上げの答え::評価できない領域を含んだ {
                件数: self.件数,
            }));
        }
        let 進んだ割合 = match 答え.面() {
            掃引が最初に触れる面::何にも触れない => 1.0,
            掃引が最初に触れる面::触れる(接触) => self
                .接地
                .接触余白()
                .余白を残して止まる割合を求める(接触.動けた割合(), 変位, 接触.接触の単位法線())
                .値(),
        };
        if 変位.長さ() * 進んだ割合 <= self.接地.接触余白().長さ() {
            return Ok(掃引の続き::打ち切る(持ち上げの答え::捨てた { 件数: self.件数 }));
        }
        self.足元 = self.足元.局所の変位を足す(変位.比で伸ばす(進んだ割合));
        Ok(掃引の続き::続ける { 進んだ割合 })
    }

    fn 下へ掃引する<口: 世界の形を尋ねる口>(
        mut self,
        口: &mut 口,
        持ち上げた長さ: メートル,
    ) -> Result<持ち上げの答え, 口::問い合わせエラー> {
        let 答え = self.接地.下へ探る(口, self.足元, 持ち上げた長さ)?;
        self.件数 = self.件数.一件数える();
        Ok(match 答え {
            下へ探った答え::歩ける面に触れた { 据えた足元, .. } => 持ち上げの答え::持ち上げた {
                足元: 据えた足元,
                件数: self.件数,
            },
            下へ探った答え::歩ける面に触れなかった => 持ち上げの答え::捨てた { 件数: self.件数 },
            下へ探った答え::評価できない領域を含んだ => {
                持ち上げの答え::評価できない領域を含んだ { 件数: self.件数 }
            }
        })
    }
}
