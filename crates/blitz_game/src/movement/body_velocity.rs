//! 胴体の速度: 水平の速度と鉛直の速度の対。空中の移動状態が持ち、掃引と滑りの反復が接触の面に沿わせる。
//!
//! 鉛直を水平と別の成分で持つのは、重力が鉛直だけを進め、落下の上限が鉛直だけに掛かるためである。
//! 面に沿わせる演算は3成分を一度に扱うため、1秒ぶんの変位へ写してから変位の代数を使う。

use blitz_math::{メートル, メートル毎秒, メートル毎秒毎秒, ワールド, 変位, 方向, 秒};

use super::horizontal_velocity::水平の速度;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 胴体の速度 {
    水平: 水平の速度,
    鉛直: メートル毎秒, // 正が上向き
}

impl 胴体の速度 {
    pub fn 静止() -> Self {
        Self::生成する(水平の速度::零(), メートル毎秒::生成する(0.0))
    }

    pub fn 生成する(水平: 水平の速度, 鉛直: メートル毎秒) -> Self {
        Self { 水平, 鉛直 }
    }

    pub fn 水平だけ(水平: 水平の速度) -> Self {
        Self::生成する(水平, メートル毎秒::生成する(0.0))
    }

    pub fn 水平(&self) -> 水平の速度 {
        self.水平
    }

    pub fn 鉛直(&self) -> メートル毎秒 {
        self.鉛直
    }

    pub fn 刻みぶんの変位を求める(&self, 刻み: 秒) -> 変位<ワールド> {
        self.水平.刻みぶんの変位を求める(刻み) + 変位::成分から生成する(メートル::生成する(0.0), self.鉛直 * 刻み, メートル::生成する(0.0))
    }

    /// 重力で鉛直の速度を1刻みぶん落とし、落下の速さの上限で切り詰めた速度。
    pub(crate) fn 重力で落とす(
        self, 重力の加速度: メートル毎秒毎秒, 刻み: 秒, 落下の速さの上限: メートル毎秒
    ) -> Self {
        let 落とした = self.鉛直 - 重力の加速度 * 刻み;
        let 上限 = メートル毎秒::生成する(-落下の速さの上限.値());
        Self::生成する(self.水平, if 落とした < 上限 { 上限 } else { 落とした })
    }

    /// 接触の面へ向かう成分を除いた速度。面から離れる向きの速度はそのまま残す。
    pub(crate) fn 接触面に沿わせる(self, 法線: 方向<ワールド>) -> Self {
        let 一秒ぶん = self.一秒ぶんの変位();
        if 一秒ぶん.方向に沿う長さ(法線) >= メートル::生成する(0.0) {
            return self;
        }
        Self::一秒ぶんの変位から生成する(一秒ぶん.方向の成分を除く(法線))
    }

    fn 一秒ぶんの変位(&self) -> 変位<ワールド> {
        self.刻みぶんの変位を求める(秒::生成する(1.0))
    }

    fn 一秒ぶんの変位から生成する(変位: 変位<ワールド>) -> Self {
        Self::生成する(
            水平の速度::成分から生成する(メートル毎秒::生成する(変位.x().値()), メートル毎秒::生成する(変位.z().値())),
            メートル毎秒::生成する(変位.y().値()),
        )
    }
}
