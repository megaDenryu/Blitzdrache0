//! 世界の軸で見た倒し量: 操作の2軸の倒し量を、前へ進む向きを基準に世界の東と南の成分へ写した水平のベクトル。
//! 長さは1以下であり、倒していなければ零である。
//!
//! 倒し量の長さが1を超えるときだけ縮めるのは、斜めに倒したときの速さが軸1本のときより速くならないようにするためである。
//! 移動をワールド軸に固定せず前へ進む向きを受け取るのは、画面の上へ倒したときにキツネが画面の奥へ歩くようにするためである。

use blitz_math::メートル毎秒;

use super::horizontal_velocity::水平の速度;
use crate::forward_azimuth::前へ進む向きの方位角;
use crate::game_intent::ゲームインテント;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 世界の軸で見た倒し量 {
    東成分: f32,
    南成分: f32,
}

impl 世界の軸で見た倒し量 {
    pub fn 生成する(インテント: ゲームインテント, 前へ進む向き: 前へ進む向きの方位角) -> Self {
        let 右への倒し量 = インテント.左右の倒し量.値();
        let 前への倒し量 = インテント.前後の倒し量.値();
        let 倒し量の長さ = (右への倒し量 * 右への倒し量 + 前への倒し量 * 前への倒し量).sqrt();
        let 縮める倍率 = if 倒し量の長さ > 1.0 { 1.0 / 倒し量の長さ } else { 1.0 };
        let 前の向き = 前へ進む向き.前へ進む向きの東と南の成分();
        let 右の向き = 前へ進む向き.右へ寄る向きの東と南の成分();
        Self {
            東成分: (前への倒し量 * 前の向き.東成分() + 右への倒し量 * 右の向き.東成分()) * 縮める倍率,
            南成分: (前への倒し量 * 前の向き.南成分() + 右への倒し量 * 右の向き.南成分()) * 縮める倍率,
        }
    }

    pub fn 中立か(&self) -> bool {
        self.東成分 == 0.0 && self.南成分 == 0.0
    }

    /// 倒した向きへ速さを掛けた水平の速度。倒し量の長さが1未満なら、そのぶんだけ遅い速度になる。
    pub fn 速さを掛ける(&self, 速さ: メートル毎秒) -> 水平の速度 {
        水平の速度::成分から生成する(
            メートル毎秒::生成する(self.東成分 * 速さ.値()),
            メートル毎秒::生成する(self.南成分 * 速さ.値()),
        )
    }
}
