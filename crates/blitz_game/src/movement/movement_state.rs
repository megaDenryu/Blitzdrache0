//! 移動状態: プレイヤーが今どの動き方にあるかの枝。初版は接地中と空中の2枝であり、登攀・滑空・水面・水中は将来足す枝である。
//!
//! 空中の枝が鉛直の速度だけでなく水平の速度も持つのは、判断6が「空中は前の刻みの水平の速度を保つ」と求めるためであり、
//! 保つ値の置き場がこの枝の中にしか無い。遷移を決めるのは接地判定の1箇所だけである(判断5)。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断5」

use blitz_math::{ラジアン, ワールド, 方向};

use super::body_velocity::胴体の速度;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 移動状態 {
    接地中 { 接地面の単位法線: 方向<ワールド> }, // 移動は接地面に沿う
    空中 { 速度: 胴体の速度 },                   // ジャンプの直後も落下中もこの枝であり、鉛直の速度の符号が上昇と下降を表す
}

impl 移動状態 {
    /// まだ接地を確かめていない開始時の状態。最初の刻みの接地判定が接地中か空中かを決める。
    pub fn 開始時は空中で静止している() -> Self {
        Self::空中 {
            速度: 胴体の速度::静止()
        }
    }

    /// 枝の呼び名。計器と報告が出す。
    pub fn 呼び名(self) -> &'static str {
        match self {
            Self::接地中 { .. } => "接地中",
            Self::空中 { .. } => "空中",
        }
    }

    /// 接地面の単位法線と鉛直のなす角。歩ける斜面の限界と比べる角であり、計器が接地面の角として出す。
    pub fn 法線と鉛直のなす角(法線: 方向<ワールド>) -> ラジアン {
        ラジアン::生成する(法線.y().clamp(-1.0, 1.0).acos())
    }
}
