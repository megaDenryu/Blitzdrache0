//! 水平の速度: 東と南の2成分で表した、鉛直の成分を持たない速度。歩く・走る・空中で保つ水平の速さがこの型で流れる。
//!
//! 2成分をメートル毎秒で持つのは、方向と速さの対で持つと速さ0のときに方向が定まらず、零の速度を表せないためである。

use std::ops::Add;

use blitz_math::{メートル, メートル毎秒, ワールド, 変位, 秒};

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 水平の速度 {
    東成分: メートル毎秒,
    南成分: メートル毎秒,
}

impl 水平の速度 {
    pub fn 零() -> Self {
        Self::成分から生成する(メートル毎秒::生成する(0.0), メートル毎秒::生成する(0.0))
    }

    pub fn 成分から生成する(東成分: メートル毎秒, 南成分: メートル毎秒) -> Self {
        Self { 東成分, 南成分 }
    }

    pub fn 東成分(&self) -> メートル毎秒 {
        self.東成分
    }

    pub fn 南成分(&self) -> メートル毎秒 {
        self.南成分
    }

    /// 向きによらない速さ。計器が水平の速さとして出す値である。
    pub fn 速さ(&self) -> メートル毎秒 {
        let 東 = self.東成分.値();
        let 南 = self.南成分.値();
        メートル毎秒::生成する((東 * 東 + 南 * 南).sqrt())
    }

    /// この速度で刻みの時間だけ進む変位。天頂成分は0である。
    pub fn 刻みぶんの変位を求める(&self, 刻み: 秒) -> 変位<ワールド> {
        変位::成分から生成する(self.東成分 * 刻み, メートル::生成する(0.0), self.南成分 * 刻み)
    }
}

impl Add for 水平の速度 {
    type Output = Self;

    fn add(self, 右辺: Self) -> Self {
        Self::成分から生成する(self.東成分 + 右辺.東成分, self.南成分 + 右辺.南成分)
    }
}
