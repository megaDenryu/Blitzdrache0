//! 滑りの答え: 掃引と滑りの反復を終えた答えの型。動いた選択肢は足元・速度・件数と、反復の途中で壁のような面へ最初に触れた
//! 事実(段差の持ち上げの入力)を持つ。評価できない領域を含んだ選択肢は、それまでに動いた分も捨てる。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断6」「判断7」

use blitz_design::{M不変データ, M値オブジェクト, M結果};
use blitz_math::{メートル, ワールド, 変位, 大域ワールド位置};

use super::body_velocity::胴体の速度;
use super::query_count::問い合わせ件数;

pub(crate) enum 滑りの答え {
    動いた(滑りの結果),
    評価できない領域を含んだ { 件数: 問い合わせ件数 },
}

impl M結果 for 滑りの答え {}

#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 滑りの結果 {
    pub(crate) 足元: 大域ワールド位置,
    pub(crate) 速度: 胴体の速度,
    pub(crate) 件数: 問い合わせ件数,
    pub(crate) 壁のような面への接触: 壁のような面への接触,
}

impl M不変データ for 滑りの結果 {}
impl M値オブジェクト for 滑りの結果 {}

// 反復の途中で壁のような面(単位法線と鉛直の角が歩ける斜面の限界より大きい面)へ最初に触れた事実。触れた刻みの足元は
// その面の手前で余白を残して止まった位置、残りの変位は面に沿わせる前の残りである。段差の持ち上げはこの位置から始め、
// 刻みの始点からそこまでに進んだ水平の距離(反復で動いた変位の水平成分の長さの和)を前へ掃引する長さの算出に使う。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) enum 壁のような面への接触 {
    触れていない,
    触れた {
        足元: 大域ワールド位置,
        残りの変位: 変位<ワールド>,
        壁へ達するまでに進んだ水平の距離: メートル,
    },
}

impl M不変データ for 壁のような面への接触 {}
impl M値オブジェクト for 壁のような面への接触 {}
