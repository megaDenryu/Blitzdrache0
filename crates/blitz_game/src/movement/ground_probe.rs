//! 接地の規則と接地判定: 1刻みの最後に足元から下向きに探る距離だけ胴体カプセルを掃引し、歩ける斜面の面に触れたら接地中、
//! 触れなければ空中と決める。移動状態の遷移を決める唯一の箇所である(判断5)。
//!
//! 接地中にする刻みは、足元を触れた高さへ据えたうえで、接触余白のぶんだけ鉛直に持ち上げる。世界の形への問い合わせは
//! 掃引の始まりで面との隔たりが半径以下なら「始まりから触れている」として動けた割合0を答えるため、面の上へ寸分の隙間も無く
//! 立たせると、面に沿う次の刻みの掃引が一歩も動けなくなる。余白は面に垂直に測って一定になるよう、法線の鉛直成分で割る。
//! 持ち上げを鉛直にするのは、法線に沿って持ち上げると斜面で毎刻み水平にずれ、立っているだけで滑り落ちるためである。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断5」「判断6」、`_doc/計画/ユビキタス言語.md`「接触余白」

use blitz_math::{メートル, ラジアン, ワールド, 変位, 大域ワールド位置, 方向, 符号付きの座標軸};

use super::body_velocity::胴体の速度;
use super::movement_state::移動状態;
use crate::body_capsule::胴体カプセル;
use crate::sweep_completeness::掃引の完全性;
use crate::sweep_hit::掃引が最初に触れる面;
use crate::world_shape_port::世界の形を尋ねる口;

const 初版の探る距離メートル: f32 = 0.1;
const 初版の歩ける斜面の限界の度: f32 = 45.0;
/// 面との隔たりに残す余白。問い合わせの丸めの食い込み(数ULP)より十分に大きく、絵では見えない長さを取る。
const 初版の接触余白メートル: f32 = 0.005;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接地の規則 {
    探る距離: メートル,
    歩ける斜面の限界: ラジアン,
    接触余白: メートル,
}

/// 接地判定の答え。評価できない領域を含んだ刻みは移動状態を動かさない。
pub(crate) enum 接地判定の答え {
    決めた {
        足元: 大域ワールド位置,
        移動状態: 移動状態,
    },
    評価できない領域を含んだ,
}

impl 接地の規則 {
    pub fn 初版の値で生成する() -> Self {
        Self {
            探る距離: メートル::生成する(初版の探る距離メートル),
            歩ける斜面の限界: ラジアン::度から(初版の歩ける斜面の限界の度),
            接触余白: メートル::生成する(初版の接触余白メートル),
        }
    }

    pub fn 接触余白(&self) -> メートル {
        self.接触余白
    }

    /// 接触の単位法線と鉛直の角が限界以下なら歩ける斜面である。
    pub fn 歩ける斜面か(&self, 法線: 方向<ワールド>) -> bool {
        法線.y() >= self.歩ける斜面の限界.値().cos()
    }

    /// 足元から下向きに探る距離だけ掃引して移動状態を決める。問い合わせは1件である。
    pub(crate) fn 判定する<口: 世界の形を尋ねる口>(
        &self,
        口: &mut 口,
        足元: 大域ワールド位置,
        速度: 胴体の速度,
    ) -> Result<接地判定の答え, 口::問い合わせエラー> {
        let 下向き = 変位::方向へ進む(方向::符号付きの座標軸から生成する(符号付きの座標軸::第二軸の負), self.探る距離);
        let 答え = 口.掃引した胴体が最初に触れる面を求める(胴体カプセル::初版の寸法で足元へ立てる(足元), 下向き)?;
        if 答え.完全性() == 掃引の完全性::評価できない領域を含む {
            return Ok(接地判定の答え::評価できない領域を含んだ);
        }
        let 空中 = 接地判定の答え::決めた {
            足元,
            移動状態: 移動状態::空中 { 速度 },
        };
        let 掃引が最初に触れる面::触れる(接触) = 答え.面() else {
            return Ok(空中);
        };
        let 法線 = 接触.接触の単位法線();
        if !self.歩ける斜面か(法線) {
            return Ok(空中);
        }
        let 持ち上げ = 変位::成分から生成する(メートル::生成する(0.0), self.接触余白 * (1.0 / 法線.y()), メートル::生成する(0.0));
        Ok(接地判定の答え::決めた {
            足元: 足元.局所の変位を足す(下向き.比で伸ばす(接触.動けた割合().値()) + 持ち上げ),
            移動状態: 移動状態::接地中 {
                接地面の単位法線: 法線
            },
        })
    }
}
