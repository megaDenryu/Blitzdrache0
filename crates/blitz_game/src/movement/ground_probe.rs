//! 接地の規則と接地判定: 探る距離・歩ける斜面の限界・接触余白の方針の定数と、1刻みの最後に足元から下向きに探る距離だけ
//! 探って歩ける斜面の面に触れたら接地中、触れなければ空中と決める接地判定を持つ。移動状態の遷移を決める唯一の箇所である(判断5)。
//! 下向きに探って歩ける面なら余白を残して据える探り方そのものは`downward_probe`にあり、段差の持ち上げも同じ探り方を使う(判断7)。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断5」「判断6」「判断7」

use blitz_math::{メートル, ラジアン, ワールド, 大域ワールド位置, 方向};

use super::body_velocity::胴体の速度;
use super::contact_margin::接触余白;
use super::downward_probe::下へ探った答え;
use super::movement_state::移動状態;
use crate::world_shape_port::世界の形を尋ねる口;

const 初版の探る距離メートル: f32 = 0.2; // 走る速さ(毎秒8メートル)×基本刻み(60分の1秒)=0.133メートルを歩ける斜面の限界(45度)の正接1で降りたときの足元の下がり0.133メートルを覆う値。稜では下端の球が稜に触れるため実際に要る降下はこれより短い(45度の稜で0.04メートル)
const 初版の歩ける斜面の限界の度: f32 = 45.0;
const 初版の接触余白メートル: f32 = 0.005; // 問い合わせの丸めの食い込み(数ULP)より十分に大きく、絵では見えない長さ

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接地の規則 {
    探る距離: メートル,
    歩ける斜面の限界: ラジアン,
    接触余白: 接触余白,
}

// 接地判定の答え。評価できない領域を含んだ刻みは移動状態を動かさない。
pub(crate) enum 接地判定の答え {
    決めた {
        足元: 大域ワールド位置,
        移動状態: 移動状態,
    },
    評価できない領域を含んだ,
}

impl 接地の規則 {
    pub fn 初版の値で生成する() -> Self {
        Self {
            探る距離: メートル::生成する(初版の探る距離メートル),
            歩ける斜面の限界: ラジアン::度から(初版の歩ける斜面の限界の度),
            接触余白: 接触余白::生成する(メートル::生成する(初版の接触余白メートル)),
        }
    }

    pub fn 接触余白(&self) -> 接触余白 {
        self.接触余白
    }

    /// 接触の単位法線と鉛直の角が限界以下なら歩ける斜面である。
    pub fn 歩ける斜面か(&self, 法線: 方向<ワールド>) -> bool {
        法線.y() >= self.歩ける斜面の限界.値().cos()
    }

    // 足元から下向きに探る距離だけ掃引して移動状態を決める。問い合わせは1件である。
    pub(crate) fn 判定する<口: 世界の形を尋ねる口>(
        &self,
        口: &mut 口,
        足元: 大域ワールド位置,
        速度: 胴体の速度,
    ) -> Result<接地判定の答え, 口::問い合わせエラー> {
        Ok(match self.下へ探る(口, 足元, self.探る距離)? {
            下へ探った答え::歩ける面に触れた {
                据えた足元,
                接地面の単位法線,
            } => 接地判定の答え::決めた {
                足元: 据えた足元,
                移動状態: 移動状態::接地中 { 接地面の単位法線 },
            },
            下へ探った答え::歩ける面に触れなかった => 接地判定の答え::決めた {
                足元,
                移動状態: 移動状態::空中 { 速度 },
            },
            下へ探った答え::評価できない領域を含んだ => 接地判定の答え::評価できない領域を含んだ,
        })
    }

    /// 軸の下端の球が段の縁の上に歩ける面として立つには、軸が縁から水平に半径×sin(歩ける斜面の限界)以内になければならない。
    /// 縁へ最初に触れた位置(軸が縁から水平に最大で半径だけ離れている)からそこまでに要る前進に、接触余白を足した長さである。
    pub fn 段差の縁に立つのに要る前進を求める(&self, 半径: メートル) -> メートル {
        半径 * (1.0 - self.歩ける斜面の限界.値().sin()) + self.接触余白.長さ()
    }
}
