//! 接地の規則と接地判定: 1刻みの最後に足元から下向きに探る距離だけ胴体カプセルを掃引し、歩ける斜面の面に触れたら接地中、
//! 触れなければ空中と決める。移動状態の遷移を決める唯一の箇所である(判断5)。
//!
//! 接地中にする刻みは、触れた瞬間の足元から掃引の経路(鉛直)に沿って接触余白のぶん戻った位置へ足元を据える。触れた瞬間の
//! 足元は接触の大域位置から組む(接触の位置から法線へ半径だけ戻った点が軸の下端である)。動けた割合から組まないのは、割合が
//! 単精度であり、立っているだけの刻みで足元が刻みごとに数ナノメートル揺れるためである。経路が鉛直であるため、
//! 斜面に立っているだけで水平にずれることはない。足元が面に隙間なく触れている(出発地点を地表の点参照で置いた直後)刻みは、
//! 下向きの掃引が始まりから触れている接触を持ち、同じ据え直しが足元を余白のぶん持ち上げる。面へ食い込んでいる(斜面の上に
//! 点参照で置いた直後)刻みは、鉛直の据え直しが食い込みを刻みごとに(1 − 法線の鉛直成分の二乗)倍へ縮め、数刻みで面の上へ出る。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断5」「判断6」、`_doc/計画/ユビキタス言語.md`「接触余白」

use blitz_math::{メートル, ラジアン, ワールド, 変位, 大域メートル, 大域ワールド位置, 方向, 符号付きの座標軸};

use super::body_velocity::胴体の速度;
use super::contact_margin::接触余白;
use super::movement_state::移動状態;
use crate::body_capsule::胴体カプセル;
use crate::sweep_completeness::掃引の完全性;
use crate::sweep_contact::掃引の接触;
use crate::sweep_hit::掃引が最初に触れる面;
use crate::world_shape_port::世界の形を尋ねる口;

const 初版の探る距離メートル: f32 = 0.2; // 走る速さ(毎秒8メートル)×基本刻み(60分の1秒)=0.133メートルを歩ける斜面の限界(45度)の正接1で降りたときの足元の下がり0.133メートルを覆う値。稜では下端の球が稜に触れるため実際に要る降下はこれより短い(45度の稜で0.04メートル)
const 初版の歩ける斜面の限界の度: f32 = 45.0;
const 初版の接触余白メートル: f32 = 0.005; // 問い合わせの丸めの食い込み(数ULP)より十分に大きく、絵では見えない長さ

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接地の規則 {
    探る距離: メートル,
    歩ける斜面の限界: ラジアン,
    接触余白: 接触余白,
}

// 接地判定の答え。評価できない領域を含んだ刻みは移動状態を動かさない。
pub(crate) enum 接地判定の答え {
    決めた {
        足元: 大域ワールド位置,
        移動状態: 移動状態,
    },
    評価できない領域を含んだ,
}

impl 接地の規則 {
    pub fn 初版の値で生成する() -> Self {
        Self {
            探る距離: メートル::生成する(初版の探る距離メートル),
            歩ける斜面の限界: ラジアン::度から(初版の歩ける斜面の限界の度),
            接触余白: 接触余白::生成する(メートル::生成する(初版の接触余白メートル)),
        }
    }

    pub fn 接触余白(&self) -> 接触余白 {
        self.接触余白
    }

    /// 接触の単位法線と鉛直の角が限界以下なら歩ける斜面である。
    pub fn 歩ける斜面か(&self, 法線: 方向<ワールド>) -> bool {
        法線.y() >= self.歩ける斜面の限界.値().cos()
    }

    // 足元から下向きに探る距離だけ掃引して移動状態を決める。問い合わせは1件である。
    pub(crate) fn 判定する<口: 世界の形を尋ねる口>(
        &self,
        口: &mut 口,
        足元: 大域ワールド位置,
        速度: 胴体の速度,
    ) -> Result<接地判定の答え, 口::問い合わせエラー> {
        let 下向き = 変位::方向へ進む(方向::符号付きの座標軸から生成する(符号付きの座標軸::第二軸の負), self.探る距離);
        let 答え = 口.掃引した胴体が最初に触れる面を求める(胴体カプセル::初版の寸法で足元へ立てる(足元), 下向き)?;
        if 答え.完全性() == 掃引の完全性::評価できない領域を含む {
            return Ok(接地判定の答え::評価できない領域を含んだ);
        }
        let 空中 = 接地判定の答え::決めた {
            足元,
            移動状態: 移動状態::空中 { 速度 },
        };
        let 掃引が最初に触れる面::触れる(接触) = 答え.面() else {
            return Ok(空中);
        };
        let 法線 = 接触.接触の単位法線();
        if !self.歩ける斜面か(法線) {
            return Ok(空中);
        }
        Ok(接地判定の答え::決めた {
            足元: self.余白を残して据えた足元を求める(足元, 接触),
            移動状態: 移動状態::接地中 {
                接地面の単位法線: 法線
            },
        })
    }

    // 接触の位置から法線へ半径だけ戻った点を軸の下端とする触れた瞬間の足元を、鉛直に余白を法線の鉛直成分で割った長さだけ
    // 持ち上げた足元。水平の2成分は掃引の始まりの足元のままである(経路が鉛直であるため)。
    fn 余白を残して据えた足元を求める(&self, 足元: 大域ワールド位置, 接触: 掃引の接触) -> 大域ワールド位置 {
        let 法線 = 接触.接触の単位法線();
        let 半径 = 胴体カプセル::初版の寸法で足元へ立てる(足元).半径();
        let 触れた瞬間の足元 =
            胴体カプセル::初版の寸法で軸の下端へ立てる(接触.接触の大域位置().局所の変位を足す(変位::方向へ進む(法線, 半径))).足元の位置();
        let 持ち上げ = self.接触余白.長さ() * (1.0 / 法線.y());
        大域ワールド位置::生成する(
            足元.x(),
            触れた瞬間の足元.y() + 大域メートル::生成する(f64::from(持ち上げ.値())),
            足元.z(),
        )
    }
}
