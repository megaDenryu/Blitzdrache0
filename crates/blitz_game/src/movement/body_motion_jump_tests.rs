//! 胴体の移動のジャンプの検査。接地中でジャンプの操作が届いた刻みに初速で空中へ移り、約0.8メートルまで上がって着地すること、
//! 空中ではジャンプの操作が無視されることを固定する(判断5)。世界と刻む手順の助けは`body_motion_test_fixture`にある。

use blitz_math::{メートル毎秒, 大域メートル};

use super::body_motion_test_fixture::{入力, 刻む, 大域位置, 床の上で接地した状態};
use super::movement_state::移動状態;
use crate::game_intent::ゲームインテント;
use crate::planar_test_world::平面と段と壁の世界;

#[test]
fn ジャンプすると約0点8メートルまで上がって着地する() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0));
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, 0.0, 0.0, 0.0);
    let ジャンプ = ゲームインテント {
        ジャンプしたいか: true,
        ..ゲームインテント::無操作()
    };
    let (mut 足元, mut 状態, _, _) = 刻む(&mut 世界, 足元, 状態, &入力(ジャンプ, 0.0), 1);
    assert!(matches!(状態, 移動状態::空中 { 速度 } if 速度.鉛直() > メートル毎秒::生成する(0.0)));
    let mut 最高点 = 足元.y().値();
    let mut 着地までの刻み = 0;
    while matches!(状態, 移動状態::空中 { .. }) && 着地までの刻み < 120 {
        (足元, 状態, _, _) = 刻む(&mut 世界, 足元, 状態, &入力(ゲームインテント::無操作(), 0.0), 1);
        最高点 = 最高点.max(足元.y().値());
        着地までの刻み += 1;
    }
    assert!(matches!(状態, 移動状態::接地中 { .. }), "{着地までの刻み}刻みで着地しなかった");
    assert!((0.7..0.9).contains(&最高点), "最高点{最高点}");
}

// 反証: 空中でジャンプの操作を受け付けると、落下中に何度でも跳び直せる。
#[test]
fn 空中ではジャンプの操作が無視される() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0));
    let ジャンプ = ゲームインテント {
        ジャンプしたいか: true,
        ..ゲームインテント::無操作()
    };
    let (_, 状態, _, _) = 刻む(
        &mut 世界,
        大域位置(0.0, 5.0, 0.0),
        移動状態::開始時は空中で静止している(),
        &入力(ジャンプ, 0.0),
        1,
    );
    let 移動状態::空中 { 速度 } = 状態 else {
        panic!("5メートルの高さから始めた刻みが空中でない");
    };
    assert!(速度.鉛直() < メートル毎秒::生成する(0.0), "鉛直の速度{}", 速度.鉛直().値());
}
