//! 落下とジャンプの規則: 重力の加速度・落下の速さの上限・ジャンプの初速の方針の定数。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断5」「判断6」

use blitz_math::{メートル毎秒, メートル毎秒毎秒};

const 初版の重力の加速度メートル毎秒毎秒: f32 = 9.8;
const 初版の落下の速さの上限メートル毎秒: f32 = 20.0;
const 初版のジャンプの初速メートル毎秒: f32 = 4.0; // 初速4.0メートル毎秒は重力9.8で約0.8メートルの高さまで上がる(初速の二乗を重力の2倍で割った値)。

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 落下とジャンプの規則 {
    重力の加速度: メートル毎秒毎秒,
    落下の速さの上限: メートル毎秒,
    ジャンプの初速: メートル毎秒,
}

impl 落下とジャンプの規則 {
    pub fn 初版の値で生成する() -> Self {
        Self {
            重力の加速度: メートル毎秒毎秒::生成する(初版の重力の加速度メートル毎秒毎秒),
            落下の速さの上限: メートル毎秒::生成する(初版の落下の速さの上限メートル毎秒),
            ジャンプの初速: メートル毎秒::生成する(初版のジャンプの初速メートル毎秒),
        }
    }

    pub fn 重力の加速度(&self) -> メートル毎秒毎秒 {
        self.重力の加速度
    }

    pub fn 落下の速さの上限(&self) -> メートル毎秒 {
        self.落下の速さの上限
    }

    pub fn ジャンプの初速(&self) -> メートル毎秒 {
        self.ジャンプの初速
    }
}
