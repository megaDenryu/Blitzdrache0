//! 速さの規則: 歩く・走る・空中で操作が変えられる水平の速さと、向きを変える速さの方針の定数。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断6」

use blitz_math::{メートル毎秒, ラジアン毎秒};

const 初版の歩く速さメートル毎秒: f32 = 4.0;
const 初版の走る速さメートル毎秒: f32 = 8.0;
const 初版の空中で操作が変えられる速さメートル毎秒: f32 = 初版の歩く速さメートル毎秒 / 2.0; // 空中で操作が水平の速度を変えられる上限は歩く速さの半分である(判断6)。
const 初版の回る速さ度毎秒: f32 = 720.0; // 毎秒720度では真後ろへの向き直りが0.25秒(15刻み)で終わり、向きが変わる過程が絵に残りつつ操作から遅れて見えない。

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 速さの規則 {
    歩く速さ: メートル毎秒,
    走る速さ: メートル毎秒,
    空中で操作が変えられる速さ: メートル毎秒,
    回る速さ: ラジアン毎秒,
}

impl 速さの規則 {
    pub fn 初版の値で生成する() -> Self {
        Self {
            歩く速さ: メートル毎秒::生成する(初版の歩く速さメートル毎秒),
            走る速さ: メートル毎秒::生成する(初版の走る速さメートル毎秒),
            空中で操作が変えられる速さ: メートル毎秒::生成する(初版の空中で操作が変えられる速さメートル毎秒),
            回る速さ: ラジアン毎秒::度毎秒から(初版の回る速さ度毎秒),
        }
    }

    /// 接地中の水平の速さ。走りたい刻みは走る速さ、そうでなければ歩く速さである。
    pub fn 接地中の速さ(&self, 走りたいか: bool) -> メートル毎秒 {
        if 走りたいか { self.走る速さ } else { self.歩く速さ }
    }

    pub fn 空中で操作が変えられる速さ(&self) -> メートル毎秒 {
        self.空中で操作が変えられる速さ
    }

    pub fn 回る速さ(&self) -> ラジアン毎秒 {
        self.回る速さ
    }
}
