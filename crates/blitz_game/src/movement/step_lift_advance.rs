//! 持ち上げの前進: 段差の持ち上げで前へ掃引する変位を、刻みの水平移動の上限から決める工程。受け取るのは望みの変位の長さと
//! 壁のような面への接触(残りの変位と壁へ達するまでに進んだ水平の距離)、返すのは前へ掃引する変位か、試みないという答えである。
//!
//! 刻みの始点からの水平移動の上限は、望みの変位の長さと「段差の縁に立つのに要る前進」(初版の値で0.078メートル)の長いほうである。
//! 前へ掃引する長さはその上限から壁へ達するまでに進んだ水平の距離を差し引いた長さであり、向きは面に沿わせる前の残りの変位の向きである。
//! 壁の位置から改めて下限だけ進む形にしないのは、歩く刻み(0.067メートル)の終端近くで蹴上げに触れると1刻みの水平移動が
//! 0.145メートルに達し、速さの上限と入力の変位を破る跳ねが見えるためである。この形では1刻みの超過は歩きで最大0.011メートル
//! (0.078−0.067)、走る刻み(0.133メートル)では起きない。歩きで届かなければその刻みの持ち上げは下へ掃引した先が縁の急な部分になって
//! 捨てられ、壁の手前で止まった次の刻みが上限いっぱいの前進で越える。前進が接触余白以下なら1件も問い合わせずに試みない。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断7」

use blitz_math::{メートル, ワールド, 変位, 大域ワールド位置};

use super::ground_probe::接地の規則;
use crate::body_capsule::胴体カプセル;

pub(crate) enum 持ち上げの前進 {
    試みない,
    前へ掃引する(変位<ワールド>),
}

impl 持ち上げの前進 {
    pub(crate) fn 求める(
        接地: &接地の規則,
        壁の手前で止まった足元: 大域ワールド位置,
        望みの変位の長さ: メートル,
        残りの変位: 変位<ワールド>,
        壁へ達するまでに進んだ水平の距離: メートル,
    ) -> Self {
        let 半径 = 胴体カプセル::初版の寸法で足元へ立てる(壁の手前で止まった足元).半径();
        let 下限 = 接地.段差の縁に立つのに要る前進を求める(半径);
        let 上限 = if 望みの変位の長さ < 下限 {
            下限
        } else {
            望みの変位の長さ
        };
        let 前進 = 上限 - 壁へ達するまでに進んだ水平の距離;
        if 前進 <= 接地.接触余白().長さ() {
            return Self::試みない;
        }
        Self::前へ掃引する(残りの変位.長さを付け替える(前進))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use blitz_math::{方向, 符号付きの座標軸};

    fn 東へ(長さ: f32) -> 変位<ワールド> {
        変位::方向へ進む(方向::符号付きの座標軸から生成する(符号付きの座標軸::第一軸の正), メートル::生成する(長さ))
    }

    fn 前へ掃引する長さ(望み: f32, 進んだ: f32) -> Option<f32> {
        let 接地 = 接地の規則::初版の値で生成する();
        match 持ち上げの前進::求める(
            &接地,
            大域ワールド位置::原点(),
            メートル::生成する(望み),
            東へ(0.01),
            メートル::生成する(進んだ),
        ) {
            持ち上げの前進::試みない => None,
            持ち上げの前進::前へ掃引する(変位) => Some(変位.長さ().値()),
        }
    }

    #[test]
    fn 歩く刻みは下限から進んだ分を引いた長さだけ前へ掃引する() {
        let 長さ = 前へ掃引する長さ(1.0 / 15.0, 0.06).unwrap_or(f32::NAN);
        assert!((長さ - 0.018).abs() < 1.0e-3, "前進{長さ}");
    }

    #[test]
    fn 走る刻みは望みの変位の長さから進んだ分を引いた長さだけ前へ掃引する() {
        let 長さ = 前へ掃引する長さ(2.0 / 15.0, 0.05).unwrap_or(f32::NAN);
        assert!((長さ - (2.0 / 15.0 - 0.05)).abs() < 1.0e-5, "前進{長さ}");
    }

    #[test]
    fn 上限まで進んだ刻みは持ち上げを試みない() {
        assert!(前へ掃引する長さ(1.0 / 15.0, 0.075).is_none());
        assert!(前へ掃引する長さ(2.0 / 15.0, 2.0 / 15.0).is_none());
    }
}
