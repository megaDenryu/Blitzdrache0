//! 胴体の移動が床の東端の稜を越えて下り斜面へ入る検査。走って歩ける斜面の限界の下り斜面へ入る刻みで接地中のままであることを
//! 固定する。世界と刻む手順の助けは`body_motion_test_fixture`にある。

use blitz_math::{ラジアン, 大域メートル};

use super::body_motion_test_fixture::{入力, 刻む, 前へ倒す, 床の上で接地した状態};
use super::movement_state::移動状態;
use crate::game_intent::ゲームインテント;
use crate::planar_test_world::平面と段と壁の世界;

/// 稜を越えた刻みの接地判定は、下端の球が稜に触れる位置(45度の稜で0.04メートルの降下)か斜面に触れる位置を答え、どちらも歩ける面である。
/// 探る距離が1刻みの水平の進みの鉛直の下がり(0.133メートル)を覆っていれば、斜面がもっと急でも刻みの途中で足元が離れない。
#[test]
fn 走って四十五度の下り斜面へ入る刻みも接地中のままである() {
    let mut 世界 = 平面と段と壁の世界::西側だけ床の世界(大域メートル::生成する(0.0), 大域メートル::生成する(0.0)).東端から東へ下る斜面を置く(
        大域メートル::生成する(0.0),
        大域メートル::生成する(0.0),
        ラジアン::度から(45.0),
    );
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, -1.0, 0.0, 0.0);
    let 走る = ゲームインテント {
        走りたいか: true,
        ..前へ倒す()
    };
    let (足元, 状態, _, 空中を経た) = 刻む(&mut 世界, 足元, 状態, &入力(走る, -90.0), 30);
    assert!(!空中を経た, "稜を越える刻みに空中を経た");
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    assert!(足元.x().値() > 1.0 && 足元.y().値() < -0.5, "東{} 天頂{}", 足元.x().値(), 足元.y().値());
}
