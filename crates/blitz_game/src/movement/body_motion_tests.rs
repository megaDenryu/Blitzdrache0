//! 胴体の移動の検査(平地・走る・壁・崖・完全性)。平面と段と壁の世界を口にして、判断6の規則を固定する。
//! 世界と刻む手順の助けは`body_motion_test_fixture`にある。

use blitz_math::{メートル毎秒, 大域メートル};

use super::body_motion_test_fixture::{入力, 刻む, 前へ倒す, 大域位置, 床の上で接地した状態};
use super::movement_state::移動状態;
use crate::game_intent::ゲームインテント;
use crate::planar_test_world::平面と段と壁の世界;

#[test]
fn 平地を北へ歩くと接地中のまま北へ進む() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0));
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, 0.0, 0.0, 0.0);
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    let (足元, 状態, 観測, 空中を経た) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), 0.0), 60);
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    assert!(!空中を経た);
    assert!((足元.z().値() + 4.0).abs() < 0.01, "南{}", 足元.z().値());
    assert!(足元.y().値() >= 0.0 && 足元.y().値() < 0.01, "天頂{}", 足元.y().値());
    assert!(
        (観測.水平の速さ - メートル毎秒::生成する(4.0)).値().abs() < 1.0e-3,
        "水平の速さ{}",
        観測.水平の速さ.値()
    );
}

#[test]
fn 走ると歩くの倍の速さで進む() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0));
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, 0.0, 0.0, 0.0);
    let 走る = ゲームインテント {
        走りたいか: true,
        ..前へ倒す()
    };
    let (足元, _, 観測, _) = 刻む(&mut 世界, 足元, 状態, &入力(走る, 0.0), 60);
    assert!((足元.z().値() + 8.0).abs() < 0.01, "南{}", 足元.z().値());
    assert!(
        (観測.水平の速さ - メートル毎秒::生成する(8.0)).値().abs() < 1.0e-3,
        "水平の速さ{}",
        観測.水平の速さ.値()
    );
}

// 反証: 計器の水平の速さを保持する速度から作ると、静止して落ちる途中に操作で動いた分が0メートル毎秒と出る。
#[test]
fn 静止して落ちる途中の操作の移動も計器の水平の速さに現れる() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0));
    let (_, 状態, 観測, _) = 刻む(
        &mut 世界,
        大域位置(0.0, 5.0, 0.0),
        移動状態::開始時は空中で静止している(),
        &入力(前へ倒す(), 0.0),
        1,
    );
    assert!(matches!(状態, 移動状態::空中 { .. }));
    assert!(
        (観測.水平の速さ - メートル毎秒::生成する(2.0)).値().abs() < 1.0e-3,
        "水平の速さ{}",
        観測.水平の速さ.値()
    );
}

// 反証: 掃引が触れても動けた割合を無視して変位の全体を動くと、足元が壁の内側へ入る。
#[test]
fn 壁に向かって歩き続けても壁の内側へ入らない() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0)).壁を置く(大域メートル::生成する(2.0));
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, 0.0, 0.0, 0.0);
    let (足元, 状態, _, _) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), 180.0), 120);
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    let 壁との隙間 = 2.0 - 足元.z().値();
    assert!(壁との隙間 >= 0.25, "足元と壁の面の距離{壁との隙間}が半径を下回った");
    assert!(壁との隙間 < 0.3, "足元と壁の面の距離{壁との隙間}が壁の手前で止まった距離より大きい");
}

#[test]
fn 崖から歩き出すと空中を経て下の床へ着地する() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0))
        .東側だけ高い床を置く(大域メートル::生成する(0.0), 大域メートル::生成する(2.0));
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, 1.0, 2.0, 0.0);
    assert!((足元.y().値() - 2.0).abs() < 0.01);
    let (足元, 状態, _, 空中を経た) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), 90.0), 120);
    assert!(空中を経た);
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    assert!(足元.y().値() < 0.01 && 足元.x().値() < 0.0, "東{} 天頂{}", 足元.x().値(), 足元.y().値());
}

// 反証: 評価できない領域を含む答えで動くと、未読込の中へ歩き込む。
#[test]
fn 完全性が保てない刻みは位置も移動状態も動かない() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0)).評価できない領域を東に置く(大域メートル::生成する(1.0));
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, 0.7, 0.0, 0.0);
    let (動いた足元, 動いた状態, 観測, _) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), -90.0), 1);
    assert_eq!(動いた足元, 足元);
    assert_eq!(動いた状態, 状態);
    assert!(観測.完全性で動かなかったか);
}
