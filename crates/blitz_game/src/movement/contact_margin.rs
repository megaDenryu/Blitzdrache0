//! 接触余白: 胴体と面の間に残す小さな隙間と、触れた掃引をその隙間が残るところで止める規則。掃引と滑りの反復と
//! 接地判定の両方がこの1つで止まる割合を決める。
//!
//! 止める位置は、接触の位置から掃引の経路に沿って戻ったところである。法線の向きへ押し戻す形にしないのは、押し戻した
//! 位置を世界の形に問い合わせていないためである。鋭角の2面の角では面Aから離す押し戻しが面Bへ食い込み、次の刻みに
//! 面Bから押すと面Aへ戻って刻みごとに振動する。掃引の経路の上の位置は、その掃引が触れるまで何にも触れないと答えた
//! 範囲にあるため、戻った位置がどの面にも食い込まない。戻る長さは、経路が面へ向かう速さ(変位と接触の単位法線の
//! 内積の符号を変えた長さ)で余白を割った割合であり、面ではちょうど余白、辺と頂点では余白以上の隔たりになる。
//! 経路が面へ向かわない(かすめる)接触では戻る割合が無限に育つため、一歩も動かないところで止める。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断6」、`_doc/計画/ユビキタス言語.md`「接触余白」

use blitz_math::{メートル, ワールド, 変位, 方向};

use crate::moved_fraction::動けた割合;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 接触余白(メートル);

impl 接触余白 {
    pub fn 生成する(余白: メートル) -> Self {
        Self(余白)
    }

    pub fn 長さ(&self) -> メートル {
        self.0
    }

    /// 触れた掃引を、接触の位置から掃引の経路に沿って戻り、面との隔たりが余白になるところで止める割合。
    pub(crate) fn 余白を残して止まる割合を求める(
        &self,
        動けた割合: 動けた割合,
        掃引の変位: 変位<ワールド>,
        接触の単位法線: 方向<ワールド>,
    ) -> 動けた割合 {
        let 面へ向かう長さ = 掃引の変位.方向に沿う長さ(接触の単位法線) * -1.0;
        if 面へ向かう長さ <= メートル::生成する(0.0) {
            return 動けた割合::一歩も動けなかった();
        }
        動けた割合.減らして零で止める(self.0 / 面へ向かう長さ)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use blitz_math::符号付きの座標軸;

    fn 割合(値: f32) -> 動けた割合 {
        match 動けた割合::生成する(値) {
            Ok(割合) => 割合,
            Err(誤り) => panic!("試験用の割合を作れなかった: {誤り}"),
        }
    }

    #[test]
    fn 面へ垂直に向かう掃引は余白の長さだけ手前で止まる() {
        let 余白 = 接触余白::生成する(メートル::生成する(0.005));
        let 下 = 方向::<ワールド>::符号付きの座標軸から生成する(符号付きの座標軸::第二軸の負);
        let 上 = 方向::<ワールド>::符号付きの座標軸から生成する(符号付きの座標軸::第二軸の正);
        let 止まる = 余白.余白を残して止まる割合を求める(割合(0.5), 変位::方向へ進む(下, メートル::生成する(0.1)), 上);
        assert!((止まる.値() - 0.45).abs() < 1.0e-6, "止まる割合{}", 止まる.値());
    }

    #[test]
    fn 余白より手前で触れた掃引とかすめる掃引は一歩も動かない() {
        let 余白 = 接触余白::生成する(メートル::生成する(0.005));
        let 下 = 方向::<ワールド>::符号付きの座標軸から生成する(符号付きの座標軸::第二軸の負);
        let 上 = 方向::<ワールド>::符号付きの座標軸から生成する(符号付きの座標軸::第二軸の正);
        let 東 = 方向::<ワールド>::符号付きの座標軸から生成する(符号付きの座標軸::第一軸の正);
        assert_eq!(
            余白
                .余白を残して止まる割合を求める(割合(0.02), 変位::方向へ進む(下, メートル::生成する(0.1)), 上)
                .値(),
            0.0
        );
        assert_eq!(
            余白
                .余白を残して止まる割合を求める(割合(0.5), 変位::方向へ進む(東, メートル::生成する(0.1)), 上)
                .値(),
            0.0
        );
    }
}
