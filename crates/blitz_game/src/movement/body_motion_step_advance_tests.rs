//! 胴体の移動の段差の持ち上げの検査(前へ掃引する長さ)。刻みの始点からの水平移動が上限(望みの変位の長さと段差の縁に立つのに
//! 要る前進の長いほう)を越えないこと、歩きで届かない刻みは壁で止まって次の刻みで越えること、走りでは触れた刻みで越えること、
//! 段の角を斜めに抜けて元の床を拾う持ち上げは捨てて滑りの結果を採ることを固定する(判断7)。
//! 越える側と捨てる側の検査は`body_motion_step_tests`と`body_motion_step_reject_tests`にある。

use blitz_math::大域メートル;

use super::body_motion_test_fixture::{入力, 刻む, 前へ倒す, 床の上で接地した状態, 水平の距離};
use super::movement_state::移動状態;
use crate::game_intent::ゲームインテント;
use crate::planar_test_world::平面と段と壁の世界;

const 段の東端: f64 = 5.0;
const 歩く刻みの変位: f64 = 4.0 / 60.0;
const 段差の縁に立つのに要る前進: f64 = 0.25 * (1.0 - std::f64::consts::FRAC_1_SQRT_2) + 0.005;

fn 段のある世界() -> 平面と段と壁の世界 {
    平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0)).段を置く(大域メートル::生成する(段の東端), 大域メートル::生成する(0.2))
}

/// 反証: 前へ掃引する長さを壁の位置から改めて下限だけ進む形に戻すと、刻みの終端近くで蹴上げに触れた刻みの水平移動が0.13メートルを越える。
#[test]
fn 刻みの始点からの水平移動は上限を越えず歩きで届かない刻みは壁で止まって次の刻みで越える() {
    let mut 世界 = 段のある世界();
    // 縁の手前で余白を残して止まる東4.751メートルの0.06メートル手前から歩き始め、最初の刻みが終端近くで縁に触れる。
    let (mut 足元, mut 状態) = 床の上で接地した状態(&mut 世界, 4.691, 0.0, 0.0);
    let mut 越えた刻み = None;
    for 刻み番号 in 0..4 {
        let (次の足元, 次の状態, 観測, _) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), -90.0), 1);
        let 動いた = 水平の距離(次の足元, 足元);
        assert!(
            動いた <= 段差の縁に立つのに要る前進 + 1.0e-4,
            "刻み{刻み番号}の水平移動{動いた}が上限を越えた"
        );
        assert!(matches!(次の状態, 移動状態::接地中 { .. }));
        if 次の足元.y().値() > 0.1 {
            越えた刻み = Some(刻み番号);
            break;
        }
        if 刻み番号 == 0 {
            assert_eq!(観測.問い合わせ件数.値(), 6, "縁に触れた最初の刻みは持ち上げを試みて捨てる");
            assert!((段の東端 - 0.26..段の東端 - 0.24).contains(&次の足元.x().値()), "東{}", 次の足元.x().値());
        }
        (足元, 状態) = (次の足元, 次の状態);
    }
    assert_eq!(越えた刻み, Some(1), "壁で止まった次の刻みで越える");
}

#[test]
fn 走りは縁に触れた刻みで越え水平移動は望みの変位を越えない() {
    let mut 世界 = 段のある世界();
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, 4.7, 0.0, 0.0);
    let 走る = ゲームインテント {
        走りたいか: true,
        ..前へ倒す()
    };
    let (次の足元, 次の状態, 観測, _) = 刻む(&mut 世界, 足元, 状態, &入力(走る, -90.0), 1);
    assert!(次の足元.y().値() > 0.1, "天頂{}", 次の足元.y().値());
    assert!(matches!(次の状態, 移動状態::接地中 { .. }));
    assert_eq!(観測.問い合わせ件数.値(), 6);
    let 動いた = 水平の距離(次の足元, 足元);
    assert!(動いた <= 2.0 * 歩く刻みの変位 + 1.0e-4, "水平移動{動いた}");
}

/// 反証: 下へ掃引した先の高さを見ずに採ると、段の角を斜めに抜ける刻みで持ち上げが角の先の床を拾い、滑りの結果より長い接線の移動を採る。
/// 角の先の床は元の床より0.007メートル高い。ちょうど同じ高さの床は、持ち上げた長さだけ下へ掃引しても余白のぶん届かないため触れず、
/// 高さの条件を待たずに捨てられる。持ち上げ前の足元(滑りの結果)は縁の稜に沿って約0.005メートル這い上がっており、角の先の床へ
/// 据えた足元(0.012メートル)はそれより接触余白以上高くない。
#[test]
fn 段の角を斜めに抜けて角の先の床を拾う持ち上げは捨てて滑りの結果を採る() {
    let 南端 = 大域メートル::生成する(0.0);
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0))
        .南端までの段を置く(大域メートル::生成する(段の東端), 大域メートル::生成する(0.2), 南端)
        .南端より南の床を置く(南端, 大域メートル::生成する(0.007));
    // 蹴上げに対して30度(東へ0.5、南へ0.866)の向きで、段の南端の角の北西から歩く。方位角-150度がこの向きである。
    let (mut 足元, mut 状態) = 床の上で接地した状態(&mut 世界, 4.74, 0.0, -0.05);
    for 刻み番号 in 0..3 {
        let (次の足元, 次の状態, _, _) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), -150.0), 1);
        let 動いた = 水平の距離(次の足元, 足元);
        assert!(動いた <= 歩く刻みの変位 + 1.0e-4, "刻み{刻み番号}の水平移動{動いた}が望みの変位を越えた");
        assert!(次の足元.y().値() < 0.02, "刻み{刻み番号}で天頂{}へ上がった", 次の足元.y().値());
        assert!(matches!(次の状態, 移動状態::接地中 { .. }));
        (足元, 状態) = (次の足元, 次の状態);
    }
    assert!(足元.z().値() > 0.0, "南{}が段の南端を抜けていない", 足元.z().値());
}
