//! 胴体の移動の斜面の検査。歩ける斜面の限界(45度)以下は接地中のまま登れ、限界より急な面は接地にならず滑り落ちることを固定する。
//! 世界と刻む手順の助けは`body_motion_test_fixture`にある。

use blitz_math::{ラジアン, 大域メートル};

use super::body_motion_test_fixture::{入力, 刻む, 前へ倒す, 大域位置};
use super::movement_state::移動状態;
use crate::game_intent::ゲームインテント;
use crate::planar_test_world::平面と段と壁の世界;

fn 東へ登る斜面の世界(水平からの角の度: f32) -> 平面と段と壁の世界 {
    平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0)).東へ登る斜面を置く(ラジアン::度から(水平からの角の度))
}

#[test]
fn 限界以下の斜面は接地中のまま登れる() {
    let mut 世界 = 東へ登る斜面の世界(30.0);
    let (足元, 状態, _, _) = 刻む(
        &mut 世界,
        大域位置(-1.0, 0.0, 0.0),
        移動状態::開始時は空中で静止している(),
        &入力(ゲームインテント::無操作(), 0.0),
        1,
    );
    let (足元, 状態, _, 空中を経た) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), -90.0), 120);
    assert!(!空中を経た);
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    assert!(足元.x().値() > 1.0 && 足元.y().値() > 0.5, "東{} 天頂{}", 足元.x().値(), 足元.y().値());
    let 移動状態::接地中 { 接地面の単位法線 } = 状態 else {
        panic!("斜面の上で接地中でない");
    };
    let 角の度 = 移動状態::法線と鉛直のなす角(接地面の単位法線).値().to_degrees();
    assert!((角の度 - 30.0).abs() < 0.5, "接地面の角{角の度}");
}

// 反証: 限界より急な面を接地中にすると、見えない壁として立ち止まるか、壁を登ってしまう。
#[test]
fn 限界より急な斜面は接地にならず滑り落ちる() {
    let mut 世界 = 東へ登る斜面の世界(60.0);
    let 斜面の上の足元 = 大域位置(1.0, 60.0_f64.to_radians().tan() + 0.2, 0.0);
    let (足元, 状態, _, _) = 刻む(
        &mut 世界,
        斜面の上の足元,
        移動状態::開始時は空中で静止している(),
        &入力(ゲームインテント::無操作(), 0.0),
        30,
    );
    assert!(matches!(状態, 移動状態::空中 { .. }));
    assert!(
        足元.x().値() < 0.9 && 足元.y().値() < 斜面の上の足元.y().値() - 0.1,
        "東{} 天頂{}",
        足元.x().値(),
        足元.y().値()
    );
}

// 反証: 急な面を押し続けて登れると、歩けない斜面の限界が意味を持たない。
#[test]
fn 限界より急な斜面は押し続けても登れない() {
    let mut 世界 = 東へ登る斜面の世界(60.0);
    let (足元, 状態, _, _) = 刻む(
        &mut 世界,
        大域位置(-1.0, 0.0, 0.0),
        移動状態::開始時は空中で静止している(),
        &入力(ゲームインテント::無操作(), 0.0),
        1,
    );
    let (足元, _, _, _) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), -90.0), 240);
    assert!(足元.y().値() < 0.5, "天頂{}", 足元.y().値());
}
