//! 胴体の移動の静止と据え直しの検査。床と斜面に立ったまま静止して位置がずれないことと、斜面へ食い込んだ足元が面の上へ
//! 出ることを固定する。角と壁の接触余白の検査は`body_motion_margin_tests`にある。
//! 世界と刻む手順の助けは`body_motion_test_fixture`にある。

use blitz_math::{ラジアン, 大域メートル};

use super::body_motion_test_fixture::{入力, 刻む, 大域位置, 床の上で接地した状態, 最も離れた成分の差};
use super::movement_state::移動状態;
use crate::game_intent::ゲームインテント;
use crate::planar_test_world::平面と段と壁の世界;

#[test]
fn 床に立ったまま静止しても位置がずれない() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0));
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, 0.0, 0.0, 0.0);
    assert!((0.004..0.006).contains(&足元.y().値()), "天頂{}", 足元.y().値());
    let (静止した足元, 状態, _, 空中を経た) = 刻む(&mut 世界, 足元, 状態, &入力(ゲームインテント::無操作(), 0.0), 60);
    assert!(!空中を経た);
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    let ずれ = 最も離れた成分の差(静止した足元, 足元);
    assert!(ずれ < 1.0e-6, "静止した足元が{ずれ}ずれた");
}

/// 反証: 余白を法線に沿って残すと、斜面に立っているだけで毎刻み水平にずれて滑り落ちる。
#[test]
fn 斜面に立ったまま静止しても滑らない() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0)).東へ登る斜面を置く(ラジアン::度から(30.0));
    let 斜面の上 = 大域位置(1.0, f64::from(30.0_f32.to_radians().tan()) + 0.5, 0.0);
    let (足元, 状態, _, _) = 刻む(
        &mut 世界,
        斜面の上,
        移動状態::開始時は空中で静止している(),
        &入力(ゲームインテント::無操作(), 0.0),
        60,
    );
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    let (静止した足元, 状態, _, 空中を経た) = 刻む(&mut 世界, 足元, 状態, &入力(ゲームインテント::無操作(), 0.0), 60);
    assert!(!空中を経た);
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    let ずれ = 最も離れた成分の差(静止した足元, 足元);
    assert!(ずれ < 1.0e-6, "斜面に立った足元が{ずれ}ずれた");
}

/// 反証: 出発地点を地表の点参照で置くと斜面では胴体が面へ食い込む。据え直しが食い込みを縮めなければ食い込んだまま歩く。
#[test]
fn 斜面へ食い込んだ足元は数刻みで面の上へ出る() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0)).東へ登る斜面を置く(ラジアン::度から(30.0));
    let 斜面の上 = 大域位置(1.0, f64::from(30.0_f32.to_radians().tan()), 0.0);
    let (足元, 状態, _, _) = 刻む(
        &mut 世界,
        斜面の上,
        移動状態::開始時は空中で静止している(),
        &入力(ゲームインテント::無操作(), 0.0),
        20,
    );
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    let 下端の高さ = 足元.y().値() + 0.25;
    let 斜面との隔たり = (下端の高さ - 足元.x().値() * f64::from(30.0_f32.to_radians().tan())) * f64::from(30.0_f32.to_radians().cos());
    assert!(斜面との隔たり >= 0.25, "軸の下端と斜面の隔たり{斜面との隔たり}が半径を下回った");
}
