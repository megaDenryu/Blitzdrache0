//! 移動の観測: 1刻みの移動が計器へ供給する値。問い合わせ件数・完全性で動かなかったか・水平の速さを持つ。
//! ゲームの状態には残さず、刻みの結果として配線へ返す。計器は開発用UIが描くだけであり、この型は開発用UIの型を名指ししない。
//!
//! 水平の速さは、その刻みに実際に動いた足元の水平の変位を刻みで割った値である。保持する速度から作ると、空中で保持する速度とは
//! 別に足す操作の変位が計器に現れない。長さ0の刻みは動きを持たないため速さ0である。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断13」

use blitz_math::{メートル, メートル毎秒, ワールド, 変位, 大域ワールド位置, 秒};

use super::query_count::問い合わせ件数;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 移動の観測 {
    pub 問い合わせ件数: 問い合わせ件数,
    pub 完全性で動かなかったか: bool, // 問い合わせの完全性が評価できない領域を含み、位置も移動状態も動かさなかった刻み
    pub 水平の速さ: メートル毎秒,
}

impl 移動の観測 {
    /// 移動を行わなかった刻み(タイトルや終了確認の裏)の観測。問い合わせは0件である。
    pub fn 移動を行わなかった刻み() -> Self {
        Self {
            問い合わせ件数: 問い合わせ件数::零(),
            完全性で動かなかったか: false,
            水平の速さ: メートル毎秒::生成する(0.0),
        }
    }

    /// 問い合わせの完全性が評価できない領域を含み、位置も移動状態も動かさなかった刻みの観測。
    pub fn 完全性で動かなかった刻み(件数: 問い合わせ件数) -> Self {
        Self {
            問い合わせ件数: 件数,
            完全性で動かなかったか: true,
            水平の速さ: メートル毎秒::生成する(0.0),
        }
    }

    /// 刻みの始まりと終わりの足元から水平の速さを求めた、動いた刻みの観測。
    pub fn 動いた刻み(
        件数: 問い合わせ件数, 刻みの始まりの足元: 大域ワールド位置, 刻みの終わりの足元: 大域ワールド位置, 刻み: 秒
    ) -> Self {
        Self {
            問い合わせ件数: 件数,
            完全性で動かなかったか: false,
            水平の速さ: 水平の速さを求める(刻みの始まりの足元, 刻みの終わりの足元, 刻み),
        }
    }
}

// 刻みの変位は単精度に収まる長さであり、収まらないなら不変条件が破れている。
fn 水平の速さを求める(
    刻みの始まりの足元: 大域ワールド位置, 刻みの終わりの足元: 大域ワールド位置, 刻み: 秒
) -> メートル毎秒 {
    if 刻み <= 秒::生成する(0.0) {
        return メートル毎秒::生成する(0.0);
    }
    let 刻みの変位 = 刻みの終わりの足元
        .局所ワールド位置へ狭める(刻みの始まりの足元)
        .unwrap_or_else(|誤り| panic!("1刻みの足元の変位が単精度に収まらない(不変条件が破れている): {誤り}"))
        .原点からの変位();
    変位::<ワールド>::成分から生成する(刻みの変位.x(), メートル::生成する(0.0), 刻みの変位.z()).長さ() / 刻み
}
