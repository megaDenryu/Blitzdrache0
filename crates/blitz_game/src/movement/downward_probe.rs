//! 下向きの探り: 足元から下向きに距離だけ胴体カプセルを掃引し、歩ける斜面の面に触れたら余白を残して据えた足元と法線を答える工程。
//! 受け取るのは足元と探る距離、返すのは下へ探った答えである。接地判定(`ground_probe`)と段差の持ち上げの下への掃引が使う。
//!
//! 据える位置は、触れた瞬間の足元から掃引の経路(鉛直)に沿って接触余白のぶん戻った位置である。触れた瞬間の足元は接触の大域位置
//! から組む(接触の位置から法線へ半径だけ戻った点が軸の下端である)。動けた割合から組まないのは、割合が単精度であり、立っている
//! だけの刻みで足元が刻みごとに数ナノメートル揺れるためである。経路が鉛直であるため、斜面に立っているだけで水平にずれることは
//! ない。足元が面に隙間なく触れている(出発地点を地表の点参照で置いた直後)刻みは、下向きの掃引が始まりから触れている接触を持ち、
//! 同じ据え直しが足元を余白のぶん持ち上げる。面へ食い込んでいる(斜面の上に点参照で置いた直後)刻みは、鉛直の据え直しが食い込みを
//! 刻みごとに(1 − 法線の鉛直成分の二乗)倍へ縮め、数刻みで面の上へ出る。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断5」「判断6」、`_doc/計画/ユビキタス言語.md`「接触余白」

use blitz_math::{メートル, ワールド, 変位, 大域メートル, 大域ワールド位置, 方向, 符号付きの座標軸};

use super::ground_probe::接地の規則;
use crate::body_capsule::胴体カプセル;
use crate::sweep_completeness::掃引の完全性;
use crate::sweep_contact::掃引の接触;
use crate::sweep_hit::掃引が最初に触れる面;
use crate::world_shape_port::世界の形を尋ねる口;

// 足元から下向きに探った答え。接地判定と、段差の持ち上げの下への掃引が同じ探り方でこれを受ける。
pub(crate) enum 下へ探った答え {
    歩ける面に触れた {
        据えた足元: 大域ワールド位置,
        接地面の単位法線: 方向<ワールド>,
    },
    歩ける面に触れなかった, // 何にも触れないか、限界より急な面に触れた
    評価できない領域を含んだ,
}

impl 接地の規則 {
    // 足元から下向きに距離だけ胴体カプセルを掃引し、歩ける斜面の面に触れたら余白を残して据えた足元と法線を答える。問い合わせは1件である。
    pub(crate) fn 下へ探る<口: 世界の形を尋ねる口>(
        &self,
        口: &mut 口,
        足元: 大域ワールド位置,
        距離: メートル,
    ) -> Result<下へ探った答え, 口::問い合わせエラー> {
        let 下向き = 変位::方向へ進む(方向::符号付きの座標軸から生成する(符号付きの座標軸::第二軸の負), 距離);
        let 答え = 口.掃引した胴体が最初に触れる面を求める(胴体カプセル::初版の寸法で足元へ立てる(足元), 下向き)?;
        if 答え.完全性() == 掃引の完全性::評価できない領域を含む {
            return Ok(下へ探った答え::評価できない領域を含んだ);
        }
        let 掃引が最初に触れる面::触れる(接触) = 答え.面() else {
            return Ok(下へ探った答え::歩ける面に触れなかった);
        };
        let 法線 = 接触.接触の単位法線();
        if !self.歩ける斜面か(法線) {
            return Ok(下へ探った答え::歩ける面に触れなかった);
        }
        Ok(下へ探った答え::歩ける面に触れた {
            据えた足元: self.余白を残して据えた足元を求める(足元, 接触),
            接地面の単位法線: 法線,
        })
    }

    // 接触の位置から法線へ半径だけ戻った点を軸の下端とする触れた瞬間の足元を、鉛直に余白を法線の鉛直成分で割った長さだけ
    // 持ち上げた足元。水平の2成分は掃引の始まりの足元のままである(経路が鉛直であるため)。
    fn 余白を残して据えた足元を求める(&self, 足元: 大域ワールド位置, 接触: 掃引の接触) -> 大域ワールド位置 {
        let 法線 = 接触.接触の単位法線();
        let 半径 = 胴体カプセル::初版の寸法で足元へ立てる(足元).半径();
        let 触れた瞬間の足元 =
            胴体カプセル::初版の寸法で軸の下端へ立てる(接触.接触の大域位置().局所の変位を足す(変位::方向へ進む(法線, 半径))).足元の位置();
        let 持ち上げ = self.接触余白().長さ() * (1.0 / 法線.y());
        大域ワールド位置::生成する(
            足元.x(),
            触れた瞬間の足元.y() + 大域メートル::生成する(f64::from(持ち上げ.値())),
            足元.z(),
        )
    }
}
