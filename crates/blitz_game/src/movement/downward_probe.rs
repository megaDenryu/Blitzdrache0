//! 下へ探った答え: 足元から下向きに距離だけ胴体カプセルを掃引した探り(`接地の規則::下へ探る`。置き場は`ground_probe`)の答えの型。
//! 接地判定と段差の持ち上げの下への掃引が同じ探り方でこれを受ける。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断5」「判断7」

use blitz_design::M結果;
use blitz_math::{ワールド, 大域ワールド位置, 方向};

// 足元から下向きに探った答え。接地判定と、段差の持ち上げの下への掃引が同じ探り方でこれを受ける。
pub(crate) enum 下へ探った答え {
    歩ける面に触れた {
        据えた足元: 大域ワールド位置,
        接地面の単位法線: 方向<ワールド>,
    },
    歩ける面に触れなかった, // 何にも触れないか、限界より急な面に触れた
    評価できない領域を含んだ,
}

impl M結果 for 下へ探った答え {}
