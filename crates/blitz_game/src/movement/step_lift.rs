//! 段差の持ち上げの規則: 段差の上限の方針の定数と、接地中に壁のような面へ触れた刻みだけ段差の持ち上げを試みる入口を持つ。
//! 1刻みの移動の手順2(掃引と滑りの反復)の後、手順3(接地判定)の前に置く工程である。
//!
//! 持ち上げを試みるのは、移動状態が接地中で、刻みの終わりに接地判定を行い(ジャンプで空中へ移る刻みは段を越える意味が無いため
//! 試みない)、滑りの反復が壁のような面へ触れ、前へ掃引する長さ(`step_lift_advance`)が接触余白より長い刻みだけである。
//! 上・前・下の3件の掃引は`step_lift_session`が持つ。持ち上げた刻みの速度は面に沿わせる前の望みの速度に戻す(壁は胴体を止めていない)。
//! 下へ掃引した先の足元が滑りの結果の足元より接触余白以上高くない刻みは、元の床を歩ける面として拾ったとみなして持ち上げを捨てる(段の縁の角を斜めに抜ける刻みで、滑りの結果を捨てて余分な接線の
//! 移動を採らないため。同じ床へ据えた2つの足元の高さは丸めの分だけ違いうるため、等しいかでなく余白で判定する)。
//! 捨てた刻みは滑りの結果をそのまま採る。3件のどれかが評価できない領域を含んだ刻みは、掃引と滑りの反復や接地判定が
//! 評価できなかった刻みと同じく、その刻み全体を動かさない(判断6の「評価できない領域を含む刻みは位置も移動状態も
//! 動かさない」を1つの規則のまま保つ。滑りの結果だけを採る形にすると、完全性で動かなかった刻みの数え方が工程ごとに違う)。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断7」

use blitz_math::{メートル, 大域ワールド位置};

use super::body_velocity::胴体の速度;
use super::desired_motion::望みの動き;
use super::ground_probe::接地の規則;
use super::movement_state::移動状態;
use super::query_count::問い合わせ件数;
use super::slide_answer::{壁のような面への接触, 滑りの結果};
use super::step_lift_advance::持ち上げの前進;
use super::step_lift_session::段差の持ち上げ;
use crate::world_shape_port::世界の形を尋ねる口;

const 初版の段差の上限メートル: f32 = 0.3;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 段差の持ち上げの規則 {
    段差の上限: メートル,
}

// 段差の持ち上げ(`step_lift_session`)の3件の掃引を終えた答え。
pub(crate) enum 持ち上げの答え {
    持ち上げた {
        足元: 大域ワールド位置,
        件数: 問い合わせ件数,
    },
    捨てた {
        件数: 問い合わせ件数,
    },
    評価できない領域を含んだ {
        件数: 問い合わせ件数,
    },
}

// 段差の持ち上げを試みた後の、接地判定へ渡す足元と速度と件数。
pub(crate) enum 持ち上げの後 {
    決まった {
        足元: 大域ワールド位置,
        速度: 胴体の速度,
        件数: 問い合わせ件数,
    },
    評価できない領域を含んだ {
        件数: 問い合わせ件数,
    },
}

impl 持ち上げの後 {
    // 持ち上げなかった(試みなかったか捨てた)刻みは滑りの足元と速度をそのまま渡す。件数は持ち上げで増えた分を含む。
    fn 滑りのまま(滑り: &滑りの結果, 件数: 問い合わせ件数) -> Self {
        Self::決まった {
            足元: 滑り.足元,
            速度: 滑り.速度,
            件数,
        }
    }
}

impl 段差の持ち上げの規則 {
    pub fn 初版の値で生成する() -> Self {
        Self {
            段差の上限: メートル::生成する(初版の段差の上限メートル),
        }
    }

    pub fn 段差の上限(&self) -> メートル {
        self.段差の上限
    }

    // 接地中で接地判定を行う刻みが壁のような面へ触れ、前へ掃引する長さが残るときだけ持ち上げを試み、それ以外の刻みは滑りの結果をそのまま返す。
    pub(crate) fn 壁に触れた滑りの後で試みる<口: 世界の形を尋ねる口>(
        &self,
        口: &mut 口,
        状態: 移動状態,
        滑り: 滑りの結果,
        望みの動き: &望みの動き,
        接地: 接地の規則,
    ) -> Result<持ち上げの後, 口::問い合わせエラー> {
        let (
            移動状態::接地中 { .. },
            true,
            壁のような面への接触::触れた {
                足元,
                残りの変位,
                壁へ達するまでに進んだ水平の距離,
            },
        ) = (状態, 望みの動き.接地判定を行うか, 滑り.壁のような面への接触)
        else {
            return Ok(持ち上げの後::滑りのまま(&滑り, 滑り.件数));
        };
        let 持ち上げの前進::前へ掃引する(前へ) =
            持ち上げの前進::求める(&接地, 足元, 望みの動き.変位, 残りの変位, 壁へ達するまでに進んだ水平の距離)
        else {
            return Ok(持ち上げの後::滑りのまま(&滑り, 滑り.件数));
        };
        match 段差の持ち上げ::始める(足元, 前へ, 滑り.件数, self.段差の上限, 接地).上へ前へ下へ掃引する(口)? {
            持ち上げの答え::持ち上げた { 足元, 件数 } if 元の床を拾ったか(足元, 滑り.足元, 接地) => {
                Ok(持ち上げの後::滑りのまま(&滑り, 件数))
            }
            持ち上げの答え::持ち上げた { 足元, 件数 } => Ok(持ち上げの後::決まった {
                足元,
                速度: 望みの動き.速度,
                件数,
            }),
            持ち上げの答え::捨てた { 件数 } => Ok(持ち上げの後::滑りのまま(&滑り, 件数)),
            持ち上げの答え::評価できない領域を含んだ { 件数 } => {
                Ok(持ち上げの後::評価できない領域を含んだ { 件数 })
            }
        }
    }
}

// 下へ掃引して据えた足元が滑りの結果の足元より接触余白以上高くなければ、持ち上げは元の床を拾っている。
fn 元の床を拾ったか(据えた足元: 大域ワールド位置, 滑りの足元: 大域ワールド位置, 接地: 接地の規則) -> bool {
    let 高くなった = 据えた足元.y().値() - 滑りの足元.y().値();
    高くなった <= f64::from(接地.接触余白().長さ().値())
}
