//! 掃引と滑りの反復: 望みの変位で胴体カプセルを掃引し、触れたら接触余白を残すところまで動いて残りの変位から接触の
//! 単位法線の成分を除いて面に沿わせ、残りが尽きるか上限まで繰り返す。1刻みの移動の手順2である。
//!
//! 触れた刻みに止まる位置は、接触の位置から掃引の経路に沿って余白のぶん戻ったところである(`contact_margin`)。
//! 法線の向きへ問い合わせなしに押し戻す形にしないのは、鋭角の2面の角でその押し戻しが隣の面へ食い込むためである。
//! 法線の成分を除くのは面へ向かう残りだけであり、面から離れる向きの残りはそのまま残す。動けた割合0で答えられた
//! (始まりで食い込んでいた)刻みに、離れる向きの動きまで削ると、食い込みから抜け出せない。
//! 面に隙間なく触れたまま面に沿う掃引が動けるのは、世界の形への問い合わせが「接触は面へ向かう掃引だけが持つ」規則を
//! 守るためであり、ここで隙間を作って補うことはしない。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断6」、`_doc/計画/ユビキタス言語.md`「接触は面へ向かう掃引だけが持つ」

use blitz_math::{メートル, ワールド, 変位, 大域ワールド位置};

use super::body_velocity::胴体の速度;
use super::contact_margin::接触余白;
use super::query_count::問い合わせ件数;
use crate::body_capsule::胴体カプセル;
use crate::sweep_completeness::掃引の完全性;
use crate::sweep_contact::掃引の接触;
use crate::sweep_hit::掃引が最初に触れる面;
use crate::world_shape_port::世界の形を尋ねる口;

pub(crate) struct 掃引と滑りの反復 {
    足元: 大域ワールド位置,
    残りの変位: 変位<ワールド>,
    速度: 胴体の速度,
    接触余白: 接触余白,
    件数: 問い合わせ件数,
}

/// 反復を終えた答え。評価できない領域を含んだ刻みは、それまでに動いた分も捨てる。
pub(crate) enum 滑りの答え {
    動いた {
        足元: 大域ワールド位置,
        速度: 胴体の速度,
        件数: 問い合わせ件数,
    },
    評価できない領域を含んだ {
        件数: 問い合わせ件数,
    },
}

enum 反復の続き {
    続ける,
    打ち切る(滑りの答え),
}

impl 掃引と滑りの反復 {
    pub(crate) fn 始める(
        足元: 大域ワールド位置, 変位: 変位<ワールド>, 速度: 胴体の速度, 接触余白: 接触余白
    ) -> Self {
        Self {
            足元,
            残りの変位: 変位,
            速度,
            接触余白,
            件数: 問い合わせ件数::零(),
        }
    }

    /// 残りが尽きるか上限の回数に達するまで掃引を繰り返す。零の変位では1件も問い合わせない。
    pub(crate) fn 上限まで反復する<口: 世界の形を尋ねる口>(
        mut self,
        口: &mut 口,
        上限: u32,
    ) -> Result<滑りの答え, 口::問い合わせエラー> {
        for _ in 0..上限 {
            if self.残りの変位.零か() {
                break;
            }
            if let 反復の続き::打ち切る(答え) = self.一回掃引する(口)? {
                return Ok(答え);
            }
        }
        Ok(滑りの答え::動いた {
            足元: self.足元,
            速度: self.速度,
            件数: self.件数,
        })
    }

    fn 一回掃引する<口: 世界の形を尋ねる口>(&mut self, 口: &mut 口) -> Result<反復の続き, 口::問い合わせエラー> {
        let 答え = 口.掃引した胴体が最初に触れる面を求める(胴体カプセル::初版の寸法で足元へ立てる(self.足元), self.残りの変位)?;
        self.件数 = self.件数.一件数える();
        if 答え.完全性() == 掃引の完全性::評価できない領域を含む {
            return Ok(反復の続き::打ち切る(滑りの答え::評価できない領域を含んだ {
                件数: self.件数,
            }));
        }
        match 答え.面() {
            掃引が最初に触れる面::何にも触れない => {
                self.足元 = self.足元.局所の変位を足す(self.残りの変位);
                self.残りの変位 = 変位::零();
            }
            掃引が最初に触れる面::触れる(接触) => self.触れた面に沿わせる(接触),
        }
        Ok(反復の続き::続ける)
    }

    fn 触れた面に沿わせる(&mut self, 接触: 掃引の接触) {
        let 法線 = 接触.接触の単位法線();
        let 止まる割合 = self.接触余白.余白を残して止まる割合を求める(接触.動けた割合(), self.残りの変位, 法線);
        let 動いた = self.残りの変位.比で伸ばす(止まる割合.値());
        self.足元 = self.足元.局所の変位を足す(動いた);
        let 残り = self.残りの変位 - 動いた;
        self.残りの変位 = if 残り.方向に沿う長さ(法線) < メートル::生成する(0.0) {
            残り.方向の成分を除く(法線)
        } else {
            残り
        };
        self.速度 = self.速度.接触面に沿わせる(法線);
    }
}
