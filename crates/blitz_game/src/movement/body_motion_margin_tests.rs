//! 胴体の移動の接触余白の検査。鋭角の2面の角で両面から半径以上離れて止まり振動しないことと、壁に隙間なく触れた足元から
//! 壁に沿って歩き出せることを固定する。静止と据え直しの検査は`body_motion_rest_tests`にある。
//! 世界と刻む手順の助けは`body_motion_test_fixture`にある。

use blitz_math::{ラジアン, 大域メートル, 大域ワールド位置};

use super::body_motion_test_fixture::{入力, 刻む, 前へ倒す, 床の上で接地した状態, 最も離れた成分の差};
use super::movement_state::移動状態;
use crate::horizontal_unit_vector::水平面の単位ベクトル;
use crate::planar_test_world::平面と段と壁の世界;

// 原点の北2メートルの点で交わる2枚の鉛直の壁。内向きの法線は互いに120度開き、内角は60度である。
fn 六十度の内角の世界() -> (平面と段と壁の世界, [[f64; 3]; 2]) {
    let 法線一覧 = [[0.75_f64.sqrt(), 0.0, 0.5], [-(0.75_f64.sqrt()), 0.0, 0.5]];
    let 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0))
        .鉛直の壁を置く(
            水平面の単位ベクトル::方位角から生成する(ラジアン::度から(240.0)),
            大域メートル::生成する(0.0),
            大域メートル::生成する(-2.0),
        )
        .鉛直の壁を置く(
            水平面の単位ベクトル::方位角から生成する(ラジアン::度から(120.0)),
            大域メートル::生成する(0.0),
            大域メートル::生成する(-2.0),
        );
    (世界, 法線一覧)
}

fn 壁からの隔たり(法線: [f64; 3], 足元: 大域ワールド位置) -> f64 {
    法線[0] * 足元.x().値() + 法線[2] * (足元.z().値() + 2.0)
}

/// 反証: 接触の位置から法線へ押し戻すと、鋭角の角で面Aから離す押し戻しが面Bへ食い込み、刻みごとに振動する。
#[test]
fn 六十度の内角へ歩いても両面から半径以上離れて止まり振動しない() {
    let (mut 世界, 法線一覧) = 六十度の内角の世界();
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, 0.0, 0.0, 0.0);
    let (足元, 状態, _, _) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), 0.0), 120);
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    assert!(足元.z().値() < -1.0, "南{}", 足元.z().値());
    for 法線 in 法線一覧 {
        let 隔たり = 壁からの隔たり(法線, 足元);
        assert!(隔たり >= 0.25, "壁からの隔たり{隔たり}が半径を下回った");
    }
    let (mut 今の足元, mut 今の状態) = (足元, 状態);
    for _ in 0..10 {
        (今の足元, 今の状態, _, _) = 刻む(&mut 世界, 今の足元, 今の状態, &入力(前へ倒す(), 0.0), 1);
        let ずれ = 最も離れた成分の差(今の足元, 足元);
        assert!(ずれ < 1.0e-6, "角で止まった足元が{ずれ}ずれた");
    }
}

/// 反証: 始まりから触れている接触を向きを問わず割合0で返すと、壁に隙間なく触れた足元から壁に沿って一歩も動けない。
#[test]
fn 壁に隙間なく触れた足元から壁に沿って歩き出せる() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0)).壁を置く(大域メートル::生成する(2.0));
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, 0.0, 0.0, 1.75);
    let (足元, 状態, _, _) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), 90.0), 60);
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    assert!((足元.x().値() + 4.0).abs() < 0.05, "東{}", 足元.x().値());
    // 西向きの倒し量の南成分は単精度の余弦の丸め(4かける10のマイナス8乗)だけ残り、平行とみなす幅の中で壁へ寄る。
    assert!(2.0 - 足元.z().値() >= 0.25 - 1.0e-5, "南{}", 足元.z().値());
}
