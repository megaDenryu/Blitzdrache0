//! 胴体の移動の段差の持ち上げの検査(越える側)。段差の上限以下の段を歩いても走っても接地中のまま越えること、上限を越える段は
//! 壁として止まること、持ち上げの3件が問い合わせ件数に数えられることを固定する(判断7)。持ち上げを捨てる側の検査は
//! `body_motion_step_reject_tests`にある。世界と刻む手順の助けは`body_motion_test_fixture`にある。

use blitz_math::大域メートル;

use super::body_motion_test_fixture::{入力, 刻む, 前へ倒す, 床の上で接地した状態};
use super::movement_state::移動状態;
use crate::game_intent::ゲームインテント;
use crate::planar_test_world::平面と段と壁の世界;

const 段の東端: f64 = 5.0;

fn 段のある世界(上面の高さ: f64) -> 平面と段と壁の世界 {
    平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0)).段を置く(大域メートル::生成する(段の東端), 大域メートル::生成する(上面の高さ))
}

/// 反証: 前へ掃引する長さを残りの変位だけにすると、歩く速さでは下へ掃引した先が常に縁の急な部分になり、段の手前で止まり続ける。
#[test]
fn 上限以下の段は歩いて接地中のまま越える() {
    let mut 世界 = 段のある世界(0.2);
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, 3.0, 0.0, 0.0);
    let (足元, 状態, _, 空中を経た) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), -90.0), 120);
    assert!(!空中を経た, "段を越える途中で空中を経た");
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    assert!(足元.x().値() > 6.0, "東{}", 足元.x().値());
    assert!((0.2..0.21).contains(&足元.y().値()), "天頂{}", 足元.y().値());
}

#[test]
fn 上限以下の段は走って接地中のまま越える() {
    let mut 世界 = 段のある世界(0.2);
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, 3.0, 0.0, 0.0);
    let 走る = ゲームインテント {
        走りたいか: true,
        ..前へ倒す()
    };
    let (足元, 状態, _, 空中を経た) = 刻む(&mut 世界, 足元, 状態, &入力(走る, -90.0), 60);
    assert!(!空中を経た, "段を越える途中で空中を経た");
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    assert!(足元.x().値() > 6.0, "東{}", 足元.x().値());
    assert!((0.2..0.21).contains(&足元.y().値()), "天頂{}", 足元.y().値());
}

/// 反証: 下へ掃引した先の面が歩けるかを見ずに採ると、段差の上限より高い段の縁へ胴体が引っ掛かり、次の刻みに空中へ落ちて揺れる。
#[test]
fn 上限を越える段は越えず壁として止まる() {
    let mut 世界 = 段のある世界(0.5);
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, 3.0, 0.0, 0.0);
    let (足元, 状態, 観測, 空中を経た) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), -90.0), 120);
    assert!(!空中を経た, "壁の手前で空中を経た");
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    assert!(足元.x().値() <= 段の東端 - 0.25, "東{}が蹴上げの内側へ入った", 足元.x().値());
    assert!(
        足元.x().値() > 段の東端 - 0.3,
        "東{}が蹴上げの手前で止まった位置より西にある",
        足元.x().値()
    );
    assert!(足元.y().値() < 0.01, "天頂{}", 足元.y().値());
    // 蹴上げの上の縁は持ち上げた軸の下端の球より0.055メートルだけ低く、前へ掃引した球は縁へ触れるまで6ミリメートル進めるため、
    // 持ち上げは下へ掃引した先(縁の急な部分)で捨てる。件数は掃引2件(縁の手前で止まった後の残りが単精度の丸めで零でない)と
    // 持ち上げ3件と接地判定1件である。
    assert_eq!(観測.問い合わせ件数.値(), 6);
}

/// 反証: 持ち上げの3件を数えないと、段を越える刻みの件数が掃引と接地判定の分だけになり、性能予算(1刻み最大7件)と突き合わせられない。
#[test]
fn 段を越える刻みの問い合わせ件数は持ち上げの3件を含む() {
    let mut 世界 = 段のある世界(0.2);
    let (mut 足元, mut 状態) = 床の上で接地した状態(&mut 世界, 4.6, 0.0, 0.0);
    let mut 越えた刻みの件数 = None;
    for _ in 0..10 {
        let 観測;
        (足元, 状態, 観測, _) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), -90.0), 1);
        if 足元.y().値() > 0.1 {
            越えた刻みの件数 = Some(観測.問い合わせ件数.値());
            break;
        }
        assert_eq!(観測.問い合わせ件数.値(), 2, "段に触れる前の刻みは掃引1件と接地判定1件である");
    }
    assert_eq!(越えた刻みの件数, Some(6), "段を越える刻みは掃引2件と持ち上げ3件と接地判定1件である");
}
