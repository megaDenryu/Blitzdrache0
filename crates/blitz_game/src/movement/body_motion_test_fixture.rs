//! 胴体の移動の検査が共有する助け。世界を組んで刻む手順と、床の上で接地した状態の作り方を持つ。
//! 検査そのものは`body_motion_tests`(平地・壁・崖・完全性)・`body_motion_jump_tests`(ジャンプ)・`body_motion_slope_tests`(斜面)にある。

use blitz_math::{ラジアン, 大域メートル, 大域ワールド位置, 秒};

use super::body_motion::胴体の移動;
use super::movement_input::一刻みの移動の入力;
use super::movement_observation::移動の観測;
use super::movement_state::移動状態;
use crate::forward_azimuth::前へ進む向きの方位角;
use crate::game_intent::ゲームインテント;
use crate::operation_axis::操作軸の倒し量;
use crate::planar_test_world::平面と段と壁の世界;

pub(crate) const 一刻み: f32 = 1.0 / 60.0;

pub(crate) fn 大域位置(東: f64, 天頂: f64, 南: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(東), 大域メートル::生成する(天頂), 大域メートル::生成する(南))
}

pub(crate) fn 前へ倒す() -> ゲームインテント {
    ゲームインテント {
        前後の倒し量: 操作軸の倒し量::押下の対から生成する(true, false),
        ..ゲームインテント::無操作()
    }
}

pub(crate) fn 入力(インテント: ゲームインテント, 前へ進む向きの度: f32) -> 一刻みの移動の入力 {
    一刻みの移動の入力 {
        インテント,
        刻み: 秒::生成する(一刻み),
        前へ進む向き: 前へ進む向きの方位角::生成する(ラジアン::度から(前へ進む向きの度)),
    }
}

/// 同じ入力で回数だけ刻み、最後の足元・移動状態・観測と、途中で空中になった刻みがあったかを返す。
pub(crate) fn 刻む(
    世界: &mut 平面と段と壁の世界,
    足元: 大域ワールド位置,
    状態: 移動状態,
    入力: &一刻みの移動の入力,
    回数: u32,
) -> (大域ワールド位置, 移動状態, 移動の観測, bool) {
    let 規則 = 胴体の移動::初版の値で生成する();
    let (mut 足元, mut 状態) = (足元, 状態);
    let mut 観測 = 移動の観測::移動を行わなかった刻み();
    let mut 空中を経た = false;
    for _ in 0..回数 {
        let 結果 = match 規則.一刻み動かす(世界, 足元, 状態, 入力) {
            Ok(結果) => 結果,
            Err(誤り) => match 誤り {},
        };
        足元 = 結果.足元();
        状態 = 結果.移動状態();
        観測 = 結果.観測();
        空中を経た |= matches!(状態, 移動状態::空中 { .. });
    }
    (足元, 状態, 観測, 空中を経た)
}

/// 床の面の高さに置いた足元を1刻み静止させ、接地判定が接地中と決めた足元と移動状態を返す。
pub(crate) fn 床の上で接地した状態(
    世界: &mut 平面と段と壁の世界,
    東: f64,
    床の高さ: f64,
    南: f64,
) -> (大域ワールド位置, 移動状態) {
    let (足元, 状態, _, _) = 刻む(
        世界,
        大域位置(東, 床の高さ, 南),
        移動状態::開始時は空中で静止している(),
        &入力(ゲームインテント::無操作(), 0.0),
        1,
    );
    (足元, 状態)
}
