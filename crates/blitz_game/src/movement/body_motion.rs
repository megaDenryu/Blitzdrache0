//! 胴体の移動: 移動状態と操作の意図から1刻みの移動を行う規則。速さ・落下とジャンプ・接地の3つの規則を持ち、
//! 世界の形を尋ねる口は刻みごとに借りて使う。キツネの場所巡りと歩くだけのゲームの両方がこの1つを使う(判断14)。
//!
//! 1刻みの手順は、望みの動きの算出(`desired_motion`)→掃引と滑りの反復(`sweep_and_slide`)→接地判定(`ground_probe`)である。
//! 問い合わせの完全性が評価できない領域を含む刻みは、位置も移動状態も動かさず、動かなかったことを観測へ数える。
//! 計器へ出す水平の速さは、その刻みに実際に動いた足元の水平の変位を刻みで割った値である。保持する速度から作ると、
//! 空中で保持する速度とは別に足す操作の変位が計器に現れない。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断6」「判断13」

use blitz_math::{メートル, メートル毎秒, ラジアン毎秒, ワールド, 変位, 大域ワールド位置, 秒};

use super::fall_jump_rules::落下とジャンプの規則;
use super::ground_probe::{接地の規則, 接地判定の答え};
use super::movement_input::一刻みの移動の入力;
use super::movement_observation::移動の観測;
use super::movement_outcome::一刻みの移動の結果;
use super::movement_state::移動状態;
use super::query_count::問い合わせ件数;
use super::speed_rules::速さの規則;
use super::sweep_and_slide::{掃引と滑りの反復, 滑りの答え};
use crate::world_shape_port::世界の形を尋ねる口;

const 掃引と滑りの反復の上限: u32 = 3; // 判断6

pub struct 胴体の移動 {
    速さ: 速さの規則,
    落下とジャンプ: 落下とジャンプの規則,
    接地: 接地の規則,
}

impl 胴体の移動 {
    pub fn 初版の値で生成する() -> Self {
        Self {
            速さ: 速さの規則::初版の値で生成する(),
            落下とジャンプ: 落下とジャンプの規則::初版の値で生成する(),
            接地: 接地の規則::初版の値で生成する(),
        }
    }

    pub fn 回る速さ(&self) -> ラジアン毎秒 {
        self.速さ.回る速さ()
    }

    pub(crate) fn 速さ(&self) -> &速さの規則 {
        &self.速さ
    }

    pub(crate) fn 落下とジャンプ(&self) -> &落下とジャンプの規則 {
        &self.落下とジャンプ
    }

    /// 足元と移動状態を1刻みぶん動かす。問い合わせの失敗は口のエラーのまま上へ返す。
    pub fn 一刻み動かす<口: 世界の形を尋ねる口>(
        &self,
        口: &mut 口,
        足元: 大域ワールド位置,
        状態: 移動状態,
        入力: &一刻みの移動の入力,
    ) -> Result<一刻みの移動の結果, 口::問い合わせエラー> {
        let 動き = self.望みの動きを求める(状態, 入力);
        let 滑り = 掃引と滑りの反復::始める(足元, 動き.変位, 動き.速度, self.接地.接触余白()).上限まで反復する(口, 掃引と滑りの反復の上限)?;
        let (動いた足元, 速度, 件数) = match 滑り {
            滑りの答え::動いた { 足元, 速度, 件数 } => (足元, 速度, 件数),
            滑りの答え::評価できない領域を含んだ { 件数 } => return Ok(動かなかった結果(足元, 状態, 件数)),
        };
        if !動き.接地判定を行うか {
            let 観測 = 観測(件数, 足元, 動いた足元, 入力.刻み);
            return Ok(一刻みの移動の結果::生成する(動いた足元, 移動状態::空中 { 速度 }, 観測));
        }
        match self.接地.判定する(口, 動いた足元, 速度)? {
            接地判定の答え::決めた {
                足元: 据えた足元, 移動状態
            } => {
                let 観測 = 観測(件数.一件数える(), 足元, 据えた足元, 入力.刻み);
                Ok(一刻みの移動の結果::生成する(据えた足元, 移動状態, 観測))
            }
            接地判定の答え::評価できない領域を含んだ => Ok(動かなかった結果(足元, 状態, 件数.一件数える())),
        }
    }
}

fn 観測(
    件数: 問い合わせ件数, 刻みの始まりの足元: 大域ワールド位置, 刻みの終わりの足元: 大域ワールド位置, 刻み: 秒
) -> 移動の観測 {
    移動の観測 {
        問い合わせ件数: 件数,
        完全性で動かなかったか: false,
        水平の速さ: 水平の速さを求める(刻みの始まりの足元, 刻みの終わりの足元, 刻み),
    }
}

// 1刻みに実際に動いた足元の水平の変位を刻みで割った速さ。長さ0の刻みは動きを持たないため速さ0である。
// 刻みの変位は単精度に収まる長さであり、収まらないなら不変条件が破れている。
fn 水平の速さを求める(
    刻みの始まりの足元: 大域ワールド位置, 刻みの終わりの足元: 大域ワールド位置, 刻み: 秒
) -> メートル毎秒 {
    if 刻み <= 秒::生成する(0.0) {
        return メートル毎秒::生成する(0.0);
    }
    let 刻みの変位 = 刻みの終わりの足元
        .局所ワールド位置へ狭める(刻みの始まりの足元)
        .unwrap_or_else(|誤り| panic!("1刻みの足元の変位が単精度に収まらない(不変条件が破れている): {誤り}"))
        .原点からの変位();
    変位::<ワールド>::成分から生成する(刻みの変位.x(), メートル::生成する(0.0), 刻みの変位.z()).長さ() / 刻み
}

fn 動かなかった結果(足元: 大域ワールド位置, 状態: 移動状態, 件数: 問い合わせ件数) -> 一刻みの移動の結果 {
    一刻みの移動の結果::生成する(
        足元,
        状態,
        移動の観測 {
            問い合わせ件数: 件数,
            完全性で動かなかったか: true,
            水平の速さ: メートル毎秒::生成する(0.0),
        },
    )
}
