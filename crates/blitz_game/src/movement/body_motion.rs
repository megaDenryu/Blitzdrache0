//! 胴体の移動: 移動状態と操作の意図から1刻みの移動を行う規則。速さ・落下とジャンプ・接地・段差の持ち上げの4つの規則を持ち、
//! 世界の形を尋ねる口は刻みごとに借りて使う。キツネの場所巡りと歩くだけのゲームの両方がこの1つを使う(判断14)。
//!
//! 1刻みの手順は、望みの動きの算出(`desired_motion`)→掃引と滑りの反復(`sweep_and_slide`)→段差の持ち上げ(`step_lift`)→
//! 接地判定(`ground_probe`)である。問い合わせの完全性が評価できない領域を含む刻みは、どの工程で出ても位置も移動状態も動かさず、
//! 動かなかったことを観測へ数える。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断6」「判断7」「判断13」

use blitz_math::{ラジアン毎秒, 大域ワールド位置};

use super::fall_jump_rules::落下とジャンプの規則;
use super::ground_probe::{接地の規則, 接地判定の答え};
use super::movement_input::一刻みの移動の入力;
use super::movement_observation::移動の観測;
use super::movement_outcome::一刻みの移動の結果;
use super::movement_state::移動状態;
use super::query_count::問い合わせ件数;
use super::slide_answer::滑りの答え;
use super::speed_rules::速さの規則;
use super::step_lift::{持ち上げの後, 段差の持ち上げの規則};
use super::sweep_and_slide::掃引と滑りの反復;
use crate::world_shape_port::世界の形を尋ねる口;

const 掃引と滑りの反復の上限: u32 = 3; // 判断6

pub struct 胴体の移動 {
    速さ: 速さの規則,
    落下とジャンプ: 落下とジャンプの規則,
    接地: 接地の規則,
    段差: 段差の持ち上げの規則,
}

impl 胴体の移動 {
    pub fn 初版の値で生成する() -> Self {
        Self {
            速さ: 速さの規則::初版の値で生成する(),
            落下とジャンプ: 落下とジャンプの規則::初版の値で生成する(),
            接地: 接地の規則::初版の値で生成する(),
            段差: 段差の持ち上げの規則::初版の値で生成する(),
        }
    }

    pub fn 回る速さ(&self) -> ラジアン毎秒 {
        self.速さ.回る速さ()
    }

    pub(crate) fn 速さ(&self) -> &速さの規則 {
        &self.速さ
    }

    pub(crate) fn 落下とジャンプ(&self) -> &落下とジャンプの規則 {
        &self.落下とジャンプ
    }

    /// 足元と移動状態を1刻みぶん動かす。問い合わせの失敗は口のエラーのまま上へ返す。
    pub fn 一刻み動かす<口: 世界の形を尋ねる口>(
        &self,
        口: &mut 口,
        足元: 大域ワールド位置,
        状態: 移動状態,
        入力: &一刻みの移動の入力,
    ) -> Result<一刻みの移動の結果, 口::問い合わせエラー> {
        let 動き = self.望みの動きを求める(状態, 入力);
        let 滑り = match 掃引と滑りの反復::始める(足元, 動き.変位, 動き.速度, self.接地).上限まで反復する(口, 掃引と滑りの反復の上限)?
        {
            滑りの答え::動いた(結果) => 結果,
            滑りの答え::評価できない領域を含んだ { 件数 } => return Ok(動かなかった結果(足元, 状態, 件数)),
        };
        let (動いた足元, 速度, 件数) = match self.段差.壁に触れた滑りの後で試みる(口, 状態, 滑り, &動き, self.接地)? {
            持ち上げの後::決まった { 足元, 速度, 件数 } => (足元, 速度, 件数),
            持ち上げの後::評価できない領域を含んだ { 件数 } => return Ok(動かなかった結果(足元, 状態, 件数)),
        };
        if !動き.接地判定を行うか {
            let 観測 = 移動の観測::動いた刻み(件数, 足元, 動いた足元, 入力.刻み);
            return Ok(一刻みの移動の結果::生成する(動いた足元, 移動状態::空中 { 速度 }, 観測));
        }
        match self.接地.判定する(口, 動いた足元, 速度)? {
            接地判定の答え::決めた {
                足元: 据えた足元, 移動状態
            } => {
                let 観測 = 移動の観測::動いた刻み(件数.一件数える(), 足元, 据えた足元, 入力.刻み);
                Ok(一刻みの移動の結果::生成する(据えた足元, 移動状態, 観測))
            }
            接地判定の答え::評価できない領域を含んだ => Ok(動かなかった結果(足元, 状態, 件数.一件数える())),
        }
    }
}

fn 動かなかった結果(足元: 大域ワールド位置, 状態: 移動状態, 件数: 問い合わせ件数) -> 一刻みの移動の結果 {
    一刻みの移動の結果::生成する(足元, 状態, 移動の観測::完全性で動かなかった刻み(件数))
}
