//! 一刻みの移動の入力: 胴体の移動が1刻みに1度受け取る値の束。操作の意図のうち胴体の移動が読む水平移動の操作と跳躍の操作・刻みの長さ・前へ進む向きを持つ。
//! 操作の意図を丸ごと持たないのは、胴体の移動が進行の操作を読まないためである。
//! 前へ進む向きを受け取るのは、その向きをカメラの方位から決めるのがコンポジションルートの配線であり、
//! ゲームロジック層がカメラの型を1つも知らないためである。

use blitz_design::{MParameter, M不変データ};
use blitz_math::秒;

use crate::forward_azimuth::前へ進む向きの方位角;
use crate::操作意図の命令::{水平移動の操作, 跳躍の操作};

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 一刻みの移動の入力 {
    水平移動の操作: 水平移動の操作,
    跳躍の操作: 跳躍の操作,
    刻み: 秒,
    前へ進む向き: 前へ進む向きの方位角,
}

impl M不変データ for 一刻みの移動の入力 {}
impl MParameter for 一刻みの移動の入力 {}

impl 一刻みの移動の入力 {
    pub fn 生成する(水平移動の操作: 水平移動の操作, 跳躍の操作: 跳躍の操作, 刻み: 秒, 前へ進む向き: 前へ進む向きの方位角) -> Self {
        Self {
            水平移動の操作,
            跳躍の操作,
            刻み,
            前へ進む向き,
        }
    }

    pub fn 水平移動の操作(&self) -> 水平移動の操作 {
        self.水平移動の操作
    }

    pub fn 跳躍の操作(&self) -> 跳躍の操作 {
        self.跳躍の操作
    }

    pub fn 刻み(&self) -> 秒 {
        self.刻み
    }

    pub fn 前へ進む向き(&self) -> 前へ進む向きの方位角 {
        self.前へ進む向き
    }
}
