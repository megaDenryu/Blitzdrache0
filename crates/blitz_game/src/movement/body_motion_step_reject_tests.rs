//! 胴体の移動の段差の持ち上げの検査(捨てる側と試みない側)。天井で持ち上げが足りない段は止まること、天井があっても持ち上げが足りれば
//! 越えること、段を越えた先が滑落する斜面なら捨てること、持ち上げの3件だけが評価できない刻みは刻み全体を動かさないこと、
//! ジャンプの刻みは蹴上げに触れても持ち上げを試みないことを固定する(判断7)。
//! 越える側の検査は`body_motion_step_tests`にある。世界と刻む手順の助けは`body_motion_test_fixture`にある。

use blitz_math::{ラジアン, 大域メートル};

use super::body_motion_test_fixture::{入力, 刻む, 前へ倒す, 床の上で接地した状態, 水平の距離};
use super::movement_state::移動状態;
use crate::game_intent::ゲームインテント;
use crate::planar_test_world::平面と段と壁の世界;

const 段の東端: f64 = 5.0;

fn 段のある世界(上面の高さ: f64) -> 平面と段と壁の世界 {
    平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0)).段を置く(大域メートル::生成する(段の東端), 大域メートル::生成する(上面の高さ))
}

/// 反証: 上へ掃引して天井に触れても段差の上限まで持ち上げると、胴体が天井の中へ入ったまま前へ進み、段の上へ乗ってしまう。
#[test]
fn 段の上の天井で持ち上げが足りなければ止まる() {
    let mut 世界 = 段のある世界(0.2).天井を置く(大域メートル::生成する(0.9));
    let (mut 足元, mut 状態) = 床の上で接地した状態(&mut 世界, 3.0, 0.0, 0.0);
    for _ in 0..120 {
        (足元, 状態, _, _) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), -90.0), 1);
        // 胴体の全高0.8メートルが高さ0.9メートルの天井の下に収まる足元は0.1メートルまでである。
        assert!(足元.y().値() < 0.1, "天頂{}が天井の下に収まらない高さへ上がった", 足元.y().値());
    }
    assert!(足元.x().値() < 段の東端 - 0.15, "東{}", 足元.x().値());
}

/// 反証: 天井に触れた持ち上げを捨てると、胴体が収まる高さの天井の下でも段を越えられない。
#[test]
fn 段の上の天井に触れても持ち上げが足りれば越える() {
    let mut 世界 = 段のある世界(0.2).天井を置く(大域メートル::生成する(1.06));
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, 3.0, 0.0, 0.0);
    let (足元, 状態, _, 空中を経た) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), -90.0), 120);
    assert!(!空中を経た);
    assert!(matches!(状態, 移動状態::接地中 { .. }));
    assert!(足元.x().値() > 6.0, "東{}", 足元.x().値());
    assert!((0.2..0.21).contains(&足元.y().値()), "天頂{}", 足元.y().値());
}

/// 反証: 下へ掃引した先が歩ける面かを見ずに採ると、段を越えた先の滑落する斜面へ胴体を乗せ、次の刻みの接地判定が空中へ落とす。
#[test]
fn 段を越えた先が滑落する斜面なら持ち上げを捨てる() {
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0))
        .蹴上げを置く(大域メートル::生成する(段の東端), 大域メートル::生成する(0.2))
        .東端から東へ登る斜面を置く(大域メートル::生成する(段の東端), 大域メートル::生成する(0.2), ラジアン::度から(60.0));
    let (mut 足元, mut 状態) = 床の上で接地した状態(&mut 世界, 4.6, 0.0, 0.0);
    let mut 最も高い足元 = 足元.y().値();
    for _ in 0..120 {
        let 観測;
        (足元, 状態, 観測, _) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), -90.0), 1);
        if 観測.問い合わせ件数.値() >= 5 {
            assert!(足元.y().値() < 0.1, "持ち上げを試みた刻みに天頂{}へ乗った", 足元.y().値());
        }
        最も高い足元 = 最も高い足元.max(足元.y().値());
    }
    assert!(最も高い足元 < 0.3, "最も高い足元{最も高い足元}");
    assert!(足元.x().値() < 段の東端 + 0.3, "東{}", 足元.x().値());
}

/// 反証: 持ち上げの掃引が評価できない領域を含む答えで動くと、胴体を未読込の上空へ持ち上げて歩き込む。
#[test]
fn 持ち上げの掃引だけが評価できない刻みは位置も移動状態も動かない() {
    let mut 世界 = 段のある世界(0.2).評価できない領域を東の上空に置く(大域メートル::生成する(段の東端), 大域メートル::生成する(0.9));
    let (mut 足元, mut 状態) = 床の上で接地した状態(&mut 世界, 4.6, 0.0, 0.0);
    let mut 止まった刻み = None;
    for 刻み番号 in 0..10 {
        let (次の足元, 次の状態, 観測, _) = 刻む(&mut 世界, 足元, 状態, &入力(前へ倒す(), -90.0), 1);
        if 観測.完全性で動かなかったか {
            assert_eq!(次の足元, 足元);
            assert_eq!(次の状態, 状態);
            assert_eq!(観測.問い合わせ件数.値(), 3, "掃引2件と持ち上げの上への1件で打ち切る");
            止まった刻み = Some(刻み番号);
            break;
        }
        assert!(次の足元.y().値() < 0.1, "天頂{}", 次の足元.y().値());
        (足元, 状態) = (次の足元, 次の状態);
    }
    assert!(止まった刻み.is_some(), "段に触れた刻みが評価できない領域を含む答えで止まらなかった");
}

/// 反証: ジャンプの刻みにも持ち上げを試みると、蹴上げに触れて跳ぶ刻みが持ち上げの3件を使って段の縁へ持ち上げられ、
/// 跳んだ高さ(0.072メートル)の倍近くまで上がる。
#[test]
fn ジャンプの刻みは蹴上げに触れても持ち上げを試みず水平移動は水平の入力を越えない() {
    let mut 世界 = 段のある世界(0.2);
    let (足元, 状態) = 床の上で接地した状態(&mut 世界, 4.76, 0.0, 0.0);
    let 前へ跳ぶ = ゲームインテント {
        ジャンプしたいか: true,
        ..前へ倒す()
    };
    let (次の足元, 次の状態, 観測, _) = 刻む(&mut 世界, 足元, 状態, &入力(前へ跳ぶ, -90.0), 1);
    assert!(matches!(次の状態, 移動状態::空中 { .. }));
    assert!(次の足元.y().値() < 0.1, "天頂{}へ持ち上げられた", 次の足元.y().値());
    assert!(観測.問い合わせ件数.値() <= 2, "持ち上げを試みた({}件)", 観測.問い合わせ件数.値());
    let 動いた = 水平の距離(次の足元, 足元);
    assert!(動いた <= 4.0 / 60.0 + 1.0e-4, "水平移動{動いた}が水平の入力を越えた");
}
