//! ゲームがどの段階にあるかの判別と、終了確認を取り消したときに戻る段階の判別を所有する。段階がどう移るかは`stage_transition`が持つ。
//!
//! タイトルを世界の切り替えでなく段階として持つのは、プレイする世界を最初から読み込んだままUIを被せる形にしたためである。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断6」。

/// ゲームの進行がどの段階にあるか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ゲームの進行段階 {
    タイトル表示中,
    場所巡り中,
    /// 終了してよいかを尋ねている段階。取り消したときに戻る段階を持つのは、タイトルから開いた確認とプレイ中に開いた確認で戻り先が違うためである。
    終了確認中 {
        取り消したときに戻る段階: 終了確認から戻る段階,
    },
    /// 終了すると決まった段階。コンポジションルートはこの段階を見てイベントループを閉じる。
    終了決定済み,
}

impl ゲームの進行段階 {
    /// 段階の呼び名。終了時の報告が「どの段階で終わったか」を出すのに使う。
    pub fn 呼び名(self) -> &'static str {
        match self {
            Self::タイトル表示中 => "タイトル表示中",
            Self::場所巡り中 => "場所巡り中",
            Self::終了確認中 { .. } => "終了確認中",
            Self::終了決定済み => "終了決定済み",
        }
    }
}

/// 終了確認を取り消したときに戻る段階。終了確認そのものと終了決定済みへは戻れないため、2枝だけを持つ。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 終了確認から戻る段階 {
    タイトル表示中,
    場所巡り中,
}

impl 終了確認から戻る段階 {
    pub fn 進行段階へ写す(self) -> ゲームの進行段階 {
        match self {
            Self::タイトル表示中 => ゲームの進行段階::タイトル表示中,
            Self::場所巡り中 => ゲームの進行段階::場所巡り中,
        }
    }
}
