//! 移動の1刻みが姿勢をどう動かすかの検査。反証したいのは、歩いた向きへ姿勢が追わずキツネが横や後ろを向いたまま滑ることと、
//! 立ち止まっているのに向きが回り続けることである。回す角そのものの検査は`向いている方位角の試験`にある。

use blitz_math::{ラジアン, 大域メートル, 大域ワールド位置, 秒};

use crate::プレイヤー::プレイヤーの状態;
use crate::前へ進む向き::前へ進む向きの方位角;
use crate::向いている方位角::動く個体が向いている方位角;
use crate::操作意図::ゲームの操作意図;
use crate::検査用の世界::平面と段と壁の世界;
use crate::確定済みの入力::{押した瞬間の操作の入力, 押下が続く操作の入力, 確定済みの操作入力};
use crate::移動::{胴体の移動, 胴体の移動の遷移パラメータ};

const 基本刻みの秒: f32 = 1.0 / 60.0;
/// 向きの比較に許す誤差。1刻みで回れる角が12度であるため、この幅は回る向きの取り違えを見逃さない。
const 許す誤差度: f32 = 1.0e-3;

fn 前へ倒した意図() -> ゲームの操作意図 {
    ゲームの操作意図::確定済みの操作入力から写す(確定済みの操作入力::生成する(
        押下が続く操作の入力::無操作().前へ進む操作を押しているかを置き換えた入力(true),
        押した瞬間の操作の入力::無操作(),
    ))
}

fn 右へ倒した意図() -> ゲームの操作意図 {
    ゲームの操作意図::確定済みの操作入力から写す(確定済みの操作入力::生成する(
        押下が続く操作の入力::無操作().右へ寄る操作を押しているかを置き換えた入力(true),
        押した瞬間の操作の入力::無操作(),
    ))
}

/// 原点で北を向いて立っている姿勢から1刻みだけ動かし、動いた後の向きを度で読む。
fn 北を向いた姿勢から胴体の移動の命令の組で動かした向きの度(意図: ゲームの操作意図, 前へ進む向き: 前へ進む向きの方位角) -> f32 {
    let 北を向いた姿勢 = プレイヤーの状態::開始時の状態を作る(大域ワールド位置::原点(), 動く個体が向いている方位角::北を向く());
    let 入力 = 胴体の移動の遷移パラメータ::生成する(秒::生成する(基本刻みの秒), 前へ進む向き);
    let mut 世界 = 平面と段と壁の世界::床だけの世界(大域メートル::生成する(0.0));
    let 移動後 = match 北を向いた姿勢.胴体の移動の命令の組で動かした状態を返す(&意図.胴体の移動の命令の組(), &胴体の移動::初版の値で生成する(), 入力, &mut 世界) {
        Ok(成功) => 成功.次の状態,
        Err(失敗) => match 失敗.失敗の理由 {},
    };
    移動後.位置と向き().向き().ラジアンで表した角().値().to_degrees()
}

fn 西を指す向き() -> 前へ進む向きの方位角 {
    前へ進む向きの方位角::生成する(ラジアン::度から(90.0))
}

/// 反証: 倒していないフレームで向きが動くと、立ち止まったキツネがその場で回り続ける。
#[test]
fn 倒していないフレームでは向きが変わらない() {
    let 向きの度 = 北を向いた姿勢から胴体の移動の命令の組で動かした向きの度(ゲームの操作意図::無操作(), 西を指す向き());
    assert!(向きの度.abs() < 許す誤差度);
}

/// 北を向いた姿勢から西へ歩き出すフレームでは、1刻みで回れる12度だけ西へ回る。西は方位角の正の側である。
#[test]
fn 横へ歩き出したフレームは1つの刻みで回れる角だけ回る() {
    let 向きの度 = 北を向いた姿勢から胴体の移動の命令の組で動かした向きの度(前へ倒した意図(), 西を指す向き());
    assert!((向きの度 - 12.0).abs() < 許す誤差度);
}

/// 反証: 右へ倒したときに前の向きのままだと、キツネが横歩きになる。前が北のとき右へ倒せば東を向く。
#[test]
fn 右へ倒したフレームは東側へ回る() {
    let 向きの度 = 北を向いた姿勢から胴体の移動の命令の組で動かした向きの度(右へ倒した意図(), 前へ進む向きの方位角::北を指す());
    assert!((向きの度 + 12.0).abs() < 許す誤差度);
}
