//! 天空状態1件を機械可読な1行へ整形する工程。受け取るのは系列名・代表時刻名・世界時刻・一日内時刻・天空状態、
//! 返すのは標準出力の1行である。値は丸めずにそのまま出す。丸めると検収が求める同一時刻の完全一致が、
//! 表示桁での一致にすり替わるためである。

use blitz_engine::sky::{天空状態, 影の有効性};
use blitz_engine::time::{一日内時刻, 世界時刻};

pub(super) fn 行を出す(系列: &str, 名前: &str, 時刻: 世界時刻, 一日内時刻: 一日内時刻, 状態: &天空状態) {
    let 方向 = 状態.太陽方向().成分();
    let 色 = 状態.方向光色().成分();
    println!(
        "天空状態行 系列={系列} 名前={名前} 世界時刻秒={} 一日内秒={} 太陽方向東={} 太陽方向天頂={} 太陽方向南={} 太陽高度度={} 昼係数={} 方向光色赤={} 方向光色緑={} 方向光色青={} 方向光強度={} 環境光強度={} 露出補正段={} 太陽天頂角度={} 濁度={} 影={}",
        時刻.紀元からの経過().値(),
        一日内時刻.一日の始まりからの経過().値(),
        方向[0],
        方向[1],
        方向[2],
        状態.太陽高度().値().to_degrees(),
        状態.昼係数().値(),
        色[0],
        色[1],
        色[2],
        状態.方向光強度().値(),
        状態.環境光強度().値(),
        状態.露出補正段().値(),
        状態.空の係数().太陽天頂角().値().to_degrees(),
        状態.空の係数().濁度().値(),
        影の表記(状態.影の有効性()),
    );
}

fn 影の表記(有効性: 影の有効性) -> &'static str {
    match 有効性 {
        影の有効性::有効 => "有効",
        影の有効性::無効 => "無効",
    }
}
