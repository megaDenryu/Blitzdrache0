//! 代表時刻の列を作る工程。受け取るのは一日の長さ、返すのは名前つきの世界時刻の列である。
//! 時刻はゲーム時計を等速で進めて作る。時計を通すことで、報告が読む時刻が本番と同じ進行の産物になる。

use blitz_engine::time::{ゲーム時計, 一日の長さ, 世界時刻, 時刻エラー, 時間倍率};
use blitz_math::大域秒;

/// 一日の中の位置を名前つきで並べたもの。値は一日を1とした位相であり、一日の長さを変えても同じ場面を指す。
const 代表位相列: [(&str, f64); 6] = [
    ("真夜中", 0.0),
    ("夜明け", 0.25),
    ("朝", 0.375),
    ("正午", 0.5),
    ("夕方", 0.75),
    ("夜", 0.875),
];

pub(super) struct 代表時刻 {
    pub(super) 名前: &'static str,
    pub(super) 時刻: 世界時刻,
}

/// 紀元(一日の始まり)に置いた時計を等速で進めながら、代表位相の時刻を順に採る。
pub(super) fn 代表時刻列を作る(一日の長さ: 一日の長さ) -> Result<Vec<代表時刻>, 時刻エラー> {
    let 一日の秒数 = f64::from(一日の長さ.秒数().値());
    let mut 時計 = ゲーム時計::生成する(世界時刻::紀元(), 時間倍率::等速());
    let mut 直前の位相 = 0.0;
    let mut 一覧 = Vec::new();
    for (名前, 位相) in 代表位相列 {
        時計.進める(大域秒::生成する((位相 - 直前の位相) * 一日の秒数))?;
        直前の位相 = 位相;
        一覧.push(代表時刻 {
            名前, 時刻: 時計.現在時刻()
        });
    }
    Ok(一覧)
}
