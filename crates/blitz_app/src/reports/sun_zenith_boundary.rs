//! 太陽天頂区間の境界表の報告。ウィンドウもレンダラーも作らず、目視見本の庭が選ぶ世界の空方針と間引きの刻みの
//! 設定から、一日で跨ぐ境界を機械可読な行として標準出力へ出す。
//!
//! これが境界の一覧の唯一の出どころである。段差を撮る`cargo xtask ibl-step`はこの行を読んで何本撮るかを決め、
//! 撮る実行そのものも同じ列挙を通る。検収側が刻みや球面天文学を写した表を持つと、刻みを変えた実行と検収が
//! 別の境界を見る。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」

use std::process::ExitCode;

use blitz_engine::sky::{一日の区間境界を列挙する, 世界の空方針, 太陽天頂区間の境界, 間引きの刻みの設定};

pub(crate) fn 太陽天頂区間の境界表を出す() -> ExitCode {
    match 報告する() {
        Ok(()) => ExitCode::SUCCESS,
        Err(誤り) => {
            eprintln!("太陽天頂区間の境界報告に失敗した: {誤り}");
            ExitCode::FAILURE
        }
    }
}

fn 報告する() -> Result<(), String> {
    let 世界の空方針::空あり { 空と太陽, .. } = 世界の空方針::空ありの既定() else {
        return Err("空ありの既定が空なしを返した".to_string());
    };
    let 刻み = 間引きの刻みの設定::初期値();
    let 一覧 = 一日の区間境界を列挙する(&空と太陽, 刻み).map_err(|誤り| format!("境界を列挙できなかった: {誤り}"))?;
    println!(
        "太陽天頂区間の境界報告 区間の数={} 境界の総数={} 一日の秒数={}",
        刻み.区間の数().get(),
        一覧.len(),
        空と太陽.天球().一日の長さ().秒数().値()
    );
    for (番号, 境界) in 一覧.iter().enumerate() {
        行を出す(番号, *境界, 刻み)?;
    }
    Ok(())
}

/// 1つの境界の行。前後の代表天頂余弦まで出すのは、段差がこの2つの値の差から生じるためであり、
/// 読み手が境界の識別から代表値を導き直さずに済ませるためである。
fn 行を出す(番号: usize, 境界: 太陽天頂区間の境界, 刻み: 間引きの刻みの設定) -> Result<(), String> {
    let 上側 = 境界.上側の区間();
    let 下側の識別 = 上側
        .区間識別()
        .checked_sub(1)
        .ok_or_else(|| "いちばん下の区間に下側の区間が無い".to_string())?;
    let 下側 = blitz_engine::sky::太陽天頂区間::識別から作る(下側の識別, 刻み).map_err(|誤り| format!("下側の区間を作れなかった: {誤り}"))?;
    println!(
        "太陽天頂区間の境界 番号={番号} 上側の区間識別={} 境界の天頂余弦={:.9} 下側の代表天頂余弦={:.9} 上側の代表天頂余弦={:.9} 最初に跨いだ一日内秒={:.6}",
        上側.区間識別(),
        上側.下端の天頂余弦(),
        下側.代表天頂余弦().値(),
        上側.代表天頂余弦().値(),
        境界.最初に跨いだ一日内秒()
    );
    Ok(())
}
