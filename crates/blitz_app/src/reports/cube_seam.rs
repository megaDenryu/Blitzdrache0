mod edge_pairs;
mod nearest_texel;
#[cfg(test)]
mod seam_tests;
pub(crate) mod texel_access;

use blitz_render::cube_image::立方体の全面;

use edge_pairs::{全ての辺, 相手側の辺, 辺の隣接面};
use nearest_texel::辺の上で最も近い添字;
use texel_access::{相対差, 立方体のテクセル};

/// 面境界の突き合わせの結果。
pub(crate) struct 面境界の観測 {
    pub(crate) 稜線数: usize,
    pub(crate) 最大相対差: f64,
}

pub(crate) fn 面境界を突き合わせる(読み戻し: &[[f32; 4]], 一辺: u32) -> 面境界の観測 {
    let mut 稜線数 = 0_usize;
    let mut 最大相対差 = 0.0_f64;
    for 面 in 立方体の全面 {
        for 辺 in 全ての辺 {
            let 隣 = 辺の隣接面(面, 辺);
            // 稜線1本を2度数えないよう、層番号の小さい面の側からだけ突き合わせる。
            if 隣.層番号() <= 面.層番号() {
                continue;
            }
            稜線数 += 1;
            最大相対差 = 最大相対差.max(稜線1本の最大相対差(読み戻し, 一辺, 面, 辺, 隣));
        }
    }
    面境界の観測 { 稜線数, 最大相対差 }
}

fn 稜線1本の最大相対差(
    読み戻し: &[[f32; 4]],
    一辺: u32,
    面: blitz_render::cube_image::立方体の面,
    辺: edge_pairs::面の辺,
    隣: blitz_render::cube_image::立方体の面,
) -> f64 {
    let 隣の辺 = 相手側の辺(隣, 面);
    let mut 最大 = 0.0_f64;
    for 番号 in 0..一辺 {
        let (横, 縦) = 辺.辺上の添字(番号, 一辺);
        let (隣の横, 隣の縦) = 辺の上で最も近い添字(面, 横, 縦, 隣, 隣の辺, 一辺);
        let 手前 = 立方体のテクセル(読み戻し, 面, 横, 縦, 一辺);
        let 向こう = 立方体のテクセル(読み戻し, 隣, 隣の横, 隣の縦, 一辺);
        最大 = 最大.max(相対差(手前, 向こう));
    }
    最大
}
