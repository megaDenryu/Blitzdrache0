//! 立方体画像の面境界の連続性を測る工程。受け取るのは読み戻した全テクセルと1面の一辺、
//! 返すのは突き合わせた稜線の本数と相対差の最大である。
//!
//! 見るのは、隣り合う2つの面で同じ稜線に接するテクセル同士の値の差である。この2つは半テクセルぶん離れた
//! 別々の向きを標本しているため厳密には一致しないが、焼いた量が向きについて連続であるため差は小さいはずである。
//! 差が跳ねるのは面と向きの写像が食い違ったときであり、絵では面の継ぎ目の筋として現れる。
//!
//! 側面の4本だけでなく天頂と天底の面を含む12本すべてを見るのは、側面だけでは天頂と天底の面の写像の誤りを
//! 1つも捉えられないためである(縦の添字がそのまま対応する側面どうしと違い、上下の面は稜線ごとに
//! 添字の対応の向きが変わる)。
//!
//! 相手のテクセルを添字の計算でなく向きの近さで選ぶのは、対応の向き(添字が増える側が同じか逆か)が
//! 稜線ごとに違うためである。近さで選べば対応表を持たずに済み、写像を変えても検査が追随する。

#[cfg(test)]
