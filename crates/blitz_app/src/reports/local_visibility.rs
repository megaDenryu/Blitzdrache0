//! 局所可視性補正のCPU正本とGPU出力を1行へ並べる報告。担当するのは「同じ合成深度から正本の局所可視度を
//! 焼き直し、GPUから読み戻した符号値と並べて出す」ことである。合否は判定しない。
//!
//! 突き合わせをここが行うのは、CPU正本(`blitz_render::local_visibility`)を読めるのがコンポジションルート
//! だけだからである。検収の入口は外部依存を持たない方針であり、正本の写しをもう1つ持つとその写しの正しさが
//! 検収の前提になる。
//!
//! 静止2フレームの一致を同じ行に載せるのは、標本の回転がフレームで回っていないことをこの実行で示すためである。
//! 回っていれば同じ入力の2フレームが違う符号値を返す。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「IIaの実装設計」

mod comparison;
mod shape;
mod surface_property;

pub(crate) use shape::合成深度の形;

use blitz_render::local_visibility::{局所可視度画像, 画像の寸法};
use blitz_render::局所可視度読み戻し画像;

use surface_property::面の性質;

/// 1つの形ぶんの報告を1行で出す。
pub(crate) fn 報告する(
    形: 合成深度の形, 正本: &局所可視度画像, 一枚目: &局所可視度読み戻し画像, 二枚目: &局所可視度読み戻し画像
) {
    let 寸法 = 正本.寸法();
    let 正本の符号値 = 正本.符号値列();
    let 突き合わせ = comparison::突き合わせる(&正本の符号値, 一枚目.符号値列());
    println!(
        "局所可視性行 形={} 幅={} 高さ={} 画素数={} 一致画素数={} 最大絶対誤差={} 第95百分位の誤差={} 静止一致={} {} {}",
        形.名前(),
        寸法.幅(),
        寸法.高さ(),
        突き合わせ.画素数,
        突き合わせ.一致画素数,
        突き合わせ.最大絶対誤差,
        突き合わせ.第95百分位の誤差,
        真偽(一枚目.符号値列() == 二枚目.符号値列()),
        性質を並べる("GPU", &surface_property::面の性質を読む(一枚目.符号値列(), 寸法)),
        性質を並べる("CPU", &surface_property::面の性質を読む(&正本の符号値, 寸法)),
    );
}

/// 読み戻しが成立しなかったことを同じ見出しで出す。行を出さずに黙って終えると、入口は「全項目が通った」と読む。
pub(crate) fn 見送りを報告する(形: 合成深度の形, 理由: &str) {
    println!("局所可視性行 形={} 読み戻し=見送り 理由={理由}", 形.名前());
}

/// CPU正本とGPU出力で同じ語を使う。入口は接頭辞だけで両者を読み分ける。
fn 性質を並べる(接頭辞: &str, 性質: &面の性質) -> String {
    format!(
        "{接頭辞}最小符号値={} {接頭辞}符号値の幅={} {接頭辞}中央行の底={} {接頭辞}中央行の肩={} {接頭辞}中央行の縁={} {接頭辞}横の最大隣接差={} {接頭辞}縦の最大隣接差={}",
        性質.最小符号値, 性質.符号値の幅, 性質.中央行の底, 性質.中央行の肩, 性質.中央行の縁, 性質.横の最大隣接差, 性質.縦の最大隣接差
    )
}

fn 真偽(値: bool) -> &'static str {
    if 値 { "真" } else { "偽" }
}

/// 正本と読み戻しが同じ寸法を見ていることは、注入の入口が寸法の一致を確かめた時点で保証される。
/// この関数はその保証を報告の側でもう一度名指しし、破れていたらプログラムの誤りとして落とす。
pub(crate) fn 寸法の一致を確かめる(正本の寸法: 画像の寸法, 読み戻し: &局所可視度読み戻し画像) {
    if 正本の寸法.幅() != 読み戻し.幅() || 正本の寸法.高さ() != 読み戻し.高さ() {
        panic!(
            "正本と読み戻しの寸法が違う(正本 幅{} 高さ{} 読み戻し 幅{} 高さ{})",
            正本の寸法.幅(),
            正本の寸法.高さ(),
            読み戻し.幅(),
            読み戻し.高さ()
        );
    }
}
