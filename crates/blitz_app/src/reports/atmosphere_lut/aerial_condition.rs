//! 読み戻し検査が使う空中遠近の固定観測条件を所有するモジュール。
//! 担当するのは「検査のカメラ姿勢・射影・距離範囲をどう決めるか」であり、値そのものと選んだ根拠をここが持つ。
//!
//! 本番のようにカメラから導かず固定の視錐台を置くのは、検査がウィンドウなし実行でウィンドウもカメラも持たないためである。
//! 値は本番と同じ`視錐台の向き`の形で与えるため、写像も積分も検査と本番で同じ経路を通る。

use blitz_math::メートル;
use blitz_render::atmosphere::{単位方向, 空中遠近観測条件, 視錐台の向き};

use super::report_error::大気のベイク済み画像報告エラー;

/// 検査の視錐台。正面を南(ワールドのZの負)へ向け、横は東西へ、縦は上下へ視野角90度ぶんを割り当てる。
/// 太陽を東の空へ置く条件と組み合わせることで、画面の左右に太陽の側と反対側が、上下に空と地面が入る。
const 基準の向き: [f32; 3] = [-1.0, 1.0, -1.0];
const 横の差分: [f32; 3] = [2.0, 0.0, 0.0];
const 縦の差分: [f32; 3] = [0.0, -2.0, 0.0];

/// 検査の最遠距離。地形世界の見える広がり(一辺100メートルのチャンクが5x5)を覆う長さである。
/// 1スライスの間隔は500/31で約16メートルになり、代表ボクセルの近・中・遠が意味のある距離差を持つ。
const 最遠距離メートル: f32 = 500.0;

pub(super) fn 検査の条件(
    観測高度: メートル,
    太陽天頂余弦: f32,
) -> Result<空中遠近観測条件, 大気のベイク済み画像報告エラー> {
    let 太陽横成分 = (1.0 - 太陽天頂余弦 * 太陽天頂余弦).max(0.0).sqrt();
    let 太陽方向 = 単位方向::生成する(太陽横成分, 太陽天頂余弦, 0.0)?;
    let 向き = 視錐台の向き::生成する(基準の向き, 横の差分, 縦の差分)?;
    Ok(空中遠近観測条件::生成する(
        観測高度,
        太陽方向,
        向き,
        メートル::生成する(最遠距離メートル),
    )?)
}
