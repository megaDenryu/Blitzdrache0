//! 空中遠近ボリュームの全ボクセルの統計。受け取るのは読み戻した生の4成分の列、返す代わりに1行の統計を標準出力へ出す。
//!
//! 平面のベイク済み画像と別に持つのは、4成分目が予約でなく代表透過率だからである。平面のベイク済み画像は4成分目が0であることを確かめるのに対し、
//! ここは4成分目が0以上1以下であることを確かめる。破れの意味が成分で違うため、数える対象そのものが別である。

use super::component_counts::{数え上げる, 有限な成分の最大値を求める, 有限な成分の最小値を求める};

/// 代表透過率の破れの数。有限でない・負である・1を超える、それぞれを数える。
struct 透過率の破れ {
    非有限: usize,
    負: usize,
    値域外: usize,
}

pub(super) fn 空中遠近の統計を出す(ボクセル一覧: &[[f32; 4]]) {
    let 数 = 数え上げる(ボクセル一覧);
    let 透過率の破れ = 代表透過率の破れを数える(ボクセル一覧);
    println!(
        "空中遠近統計 ボクセル数={} 非有限={} 負={} 一超え={} 透過率が値域外={} 最小={:.9} 最大={:.9}",
        ボクセル一覧.len(),
        数.非有限 + 透過率の破れ.非有限,
        数.負 + 透過率の破れ.負,
        数.上限超え,
        透過率の破れ.値域外,
        有限な成分の最小値を求める(ボクセル一覧),
        有限な成分の最大値を求める(ボクセル一覧)
    );
}

fn 代表透過率の破れを数える(ボクセル一覧: &[[f32; 4]]) -> 透過率の破れ {
    let mut 破れ = 透過率の破れ {
        非有限: 0, 負: 0, 値域外: 0
    };
    for ボクセル in ボクセル一覧 {
        let 透過率 = ボクセル[3];
        if !透過率.is_finite() {
            破れ.非有限 += 1;
            破れ.値域外 += 1;
        } else if 透過率 < 0.0 {
            破れ.負 += 1;
            破れ.値域外 += 1;
        } else if 透過率 > 1.0 {
            破れ.値域外 += 1;
        }
    }
    破れ
}
