//! 読み戻した4成分の列を、散乱の3成分について走査して破れを数える。
//! 受け取るのは読み戻した生の4成分の列、返すのは破れの件数と有限な成分の最小・最大である。
//!
//! 何を破れと数えるかの定義をここが単独で持つのは、平面のベイク済み画像と立体のボリュームで判定の一部が違っても
//! 「非有限・負・1超え」の意味は共通であり、2箇所で数え方が食い違うと報告の行の意味が読み手から見て揃わなくなるためである。

/// 有限でない・負である・1を超える、それぞれの件数と、4成分目が0でないテクセルの件数。
/// 4成分目は平面のベイク済み画像では予約であり、立体のボリュームでは代表透過率であるため、意味づけは呼び出し側が持つ。
pub(super) struct 破れの数 {
    pub(super) 非有限: usize,
    pub(super) 負: usize,
    pub(super) 上限超え: usize,
    pub(super) 第4成分が非零: usize,
}

pub(super) fn 数え上げる(テクセル一覧: &[[f32; 4]]) -> 破れの数 {
    let mut 数 = 破れの数 {
        非有限: 0,
        負: 0,
        上限超え: 0,
        第4成分が非零: 0,
    };
    for テクセル in テクセル一覧 {
        for 成分 in &テクセル[0..3] {
            if !成分.is_finite() {
                数.非有限 += 1;
            } else if *成分 < 0.0 {
                数.負 += 1;
            } else if *成分 > 1.0 {
                数.上限超え += 1;
            }
        }
        if テクセル[3] != 0.0 {
            数.第4成分が非零 += 1;
        }
    }
    数
}

pub(super) fn 最小値(テクセル一覧: &[[f32; 4]]) -> f32 {
    有限な三成分(テクセル一覧).fold(f32::INFINITY, f32::min)
}

pub(super) fn 最大値(テクセル一覧: &[[f32; 4]]) -> f32 {
    有限な三成分(テクセル一覧).fold(f32::NEG_INFINITY, f32::max)
}

fn 有限な三成分(テクセル一覧: &[[f32; 4]]) -> impl Iterator<Item = f32> + '_ {
    テクセル一覧
        .iter()
        .flat_map(|テクセル| テクセル[0..3].iter().copied())
        .filter(|値| 値.is_finite())
}
