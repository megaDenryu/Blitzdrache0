//! 読み戻した全テクセルを走査して、有限性・非負・値域の破れを数え上げる工程。
//! 受け取るのは読み戻した生の4成分の列、返す代わりに1行の統計を標準出力へ出す。
//!
//! 破れの件数を出すのは、代表テクセルの一致だけでは端や角の壊れた値を見逃すためである。
//! 4成分目は予約であり、シェーダーが0を書くことをここが確かめる。

/// 有限でない・負である・0以上1以下を外れる、それぞれの件数。
struct 破れの数 {
    非有限: usize,
    負: usize,
    上限超え: usize,
    予約が非零: usize,
}

pub(super) fn 透過率の統計を出す(テクセル一覧: &[[f32; 4]]) {
    let 数 = 数え上げる(テクセル一覧);
    println!(
        "透過率統計 テクセル数={} 非有限={} 負={} 一超え={} 予約が非零={} 最小={:.9} 最大={:.9}",
        テクセル一覧.len(),
        数.非有限,
        数.負,
        数.上限超え,
        数.予約が非零,
        最小値(テクセル一覧),
        最大値(テクセル一覧)
    );
}

pub(super) fn 多重散乱の統計を出す(テクセル一覧: &[[f32; 4]]) {
    上限の無い統計を出す("多重散乱統計", テクセル一覧);
}

pub(super) fn スカイビューの統計を出す(テクセル一覧: &[[f32; 4]]) {
    上限の無い統計を出す("スカイビュー統計", テクセル一覧);
}

/// 上限を持たない量の統計。1を超えた件数は破れでなく参考値として出す。
/// 多重散乱もスカイビューも、太陽の放射照度を1としたときの伝達率であり、地表アルベドが高い大気では1を超えうる。
fn 上限の無い統計を出す(見出し: &str, テクセル一覧: &[[f32; 4]]) {
    let 数 = 数え上げる(テクセル一覧);
    println!(
        "{見出し} テクセル数={} 非有限={} 負={} 一超え={} 予約が非零={} 最小={:.9} 最大={:.9}",
        テクセル一覧.len(),
        数.非有限,
        数.負,
        数.上限超え,
        数.予約が非零,
        最小値(テクセル一覧),
        最大値(テクセル一覧)
    );
}

fn 数え上げる(テクセル一覧: &[[f32; 4]]) -> 破れの数 {
    let mut 数 = 破れの数 {
        非有限: 0,
        負: 0,
        上限超え: 0,
        予約が非零: 0,
    };
    for テクセル in テクセル一覧 {
        for 成分 in &テクセル[0..3] {
            if !成分.is_finite() {
                数.非有限 += 1;
            } else if *成分 < 0.0 {
                数.負 += 1;
            } else if *成分 > 1.0 {
                数.上限超え += 1;
            }
        }
        if テクセル[3] != 0.0 {
            数.予約が非零 += 1;
        }
    }
    数
}

fn 最小値(テクセル一覧: &[[f32; 4]]) -> f32 {
    有限な三成分(テクセル一覧).fold(f32::INFINITY, f32::min)
}

fn 最大値(テクセル一覧: &[[f32; 4]]) -> f32 {
    有限な三成分(テクセル一覧).fold(f32::NEG_INFINITY, f32::max)
}

fn 有限な三成分(テクセル一覧: &[[f32; 4]]) -> impl Iterator<Item = f32> + '_ {
    テクセル一覧
        .iter()
        .flat_map(|テクセル| テクセル[0..3].iter().copied())
        .filter(|値| 値.is_finite())
}
