//! 代表テクセルの比較行の書式。担当するのは「見出しと座標とCPU正本の3成分とGPUの3成分から、判定側が読める1行を出す」ことである。
//!
//! 書式をここが単独で持つのは、これがblitz_appとxtaskの間の機械可読な契約そのものだからである。
//! 読み取り側は`xtask/src/atmosphere_lut/parse/row.rs`の`代表を読む`であり、項目名の対応を2箇所で保たないために
//! 平面のLUTと立体のボリュームがどちらもこの1つの書式を通る。

pub(super) fn 代表行を出す(見出し: &str, 横: u32, 縦: u32, 期待: [f32; 3], 実測: [f32; 3]) {
    println!(
        "{見出し} 横={横} 縦={縦} 期待赤={:.9} 期待緑={:.9} 期待青={:.9} 実測赤={:.9} 実測緑={:.9} 実測青={:.9}",
        期待[0], 期待[1], 期待[2], 実測[0], 実測[1], 実測[2]
    );
}
