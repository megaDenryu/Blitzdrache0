//! 実行1回ぶんを表す行の報告。担当するのはvalidation層の在否と件数、それに2回焼いた結果の突き合わせである。
//! 受け取るのは2回の読み戻し、返す代わりに行を標準出力へ出す。
//!
//! テクセルの値を見る`rows`と分けるのは、こちらが見るのが「実行そのものが健全か」であり、
//! LUTの中身が正しいかとは別の失敗の仕方を持つためである。

use blitz_render::atmosphere_lut_probe::大気LUT読み戻し;

/// validation層の在否と、2回の実行が数えた指摘の合計。件数を合計で出すのは、どちらの実行で出た指摘も
/// 同じ1つの検収を落とすべきだからである。層が無い実行の0件を有効な実行の0件と読み違えないよう、状況も同じ行へ出す。
pub(super) fn 検証を出す(一回目: &大気LUT読み戻し, 二回目: &大気LUT読み戻し) {
    println!(
        "検証層 状況={} 件数={}",
        一回目.検証層の状況().呼び名(),
        一回目.検証件数() + 二回目.検証件数()
    );
}

pub(super) fn 再現性を出す(一回目: &大気LUT読み戻し, 二回目: &大気LUT読み戻し) {
    println!(
        "再現性 透過率の不一致={} 多重散乱の不一致={} スカイビューの不一致={} 空中遠近の不一致={}",
        不一致数(一回目.透過率(), 二回目.透過率()),
        不一致数(一回目.多重散乱(), 二回目.多重散乱()),
        不一致数(一回目.スカイビュー(), 二回目.スカイビュー()),
        不一致数(一回目.空中遠近(), 二回目.空中遠近())
    );
}

/// 2回の読み戻しを1ビットも違わないかで比べる。丸めの許容を持たないのは、決定性の契約が完全一致だからである。
fn 不一致数(一回目: &[[f32; 4]], 二回目: &[[f32; 4]]) -> usize {
    if 一回目.len() != 二回目.len() {
        return 一回目.len().max(二回目.len());
    }
    一回目
        .iter()
        .zip(二回目)
        .filter(|(左, 右)| 左.iter().zip(右.iter()).any(|(左値, 右値)| 左値.to_bits() != 右値.to_bits()))
        .count()
}
