//! 平面のベイク済み画像3枚の代表テクセルの選び方と、その1テクセルずつの報告。
//! 受け取るのは読み戻した生の4成分とCPU正本の材料、返す代わりに行を標準出力へ出す。
//!
//! 代表テクセルを選ぶのは、全テクセルのCPU正本を出すと多重散乱の計算量が検収の時間に見合わないためである。
//! 端・中央・地平線付近という写像の性質が変わる位置を選び、全体の健全性は統計の行が受け持つ。
//!
//! 3枚をまとめて持つのは、参照する添字が幅と縦横の2次元であり、4成分目が予約であるという性質を3枚が共有するためである。
//! 立体のボリュームは添字も成分の意味も違うため`aerial_rows`が持つ。

use blitz_render::atmosphere::{
    スカイビューのベイク済み画像のテクセル値, スカイビュー観測条件, 多重散乱のベイク済み画像のテクセル値, 多重散乱表, 大気のベイク済み画像の解像度,
    大気散乱媒体, 大気数学エラー, 透過率のベイク済み画像のテクセル値, 透過率表,
};

use super::representative_line::代表行を出す;

/// 透過率のベイク済み画像の代表テクセル。左端・中央・右端をそれぞれ地表付近と高高度で見る。
const 透過率の代表: [(u32, u32); 6] = [(0, 0), (128, 0), (255, 0), (0, 32), (128, 32), (255, 63)];
/// 多重散乱のベイク済み画像の代表テクセル。太陽が真下・水平・真上の3つを地表付近と高高度で見る。
const 多重散乱の代表: [(u32, u32); 6] = [(0, 0), (16, 0), (31, 0), (0, 16), (16, 16), (31, 31)];
/// スカイビューのベイク済み画像の代表テクセル。写像の性質が変わる位置を選ぶ。
/// 縦は天頂(0)・空の中ほど(27)・地平線の直上(53)・地平線の直下(54)・天底(107)、横は太陽の方位(0)・真横(96)・反対の方位(191)である。
const スカイビューの代表: [(u32, u32); 8] = [(0, 0), (96, 0), (191, 0), (0, 27), (96, 27), (0, 53), (96, 54), (191, 107)];

pub(super) fn 透過率の代表テクセルを出す(
    媒体: &大気散乱媒体,
    解像度: 大気のベイク済み画像の解像度,
    読み戻し: &[[f32; 4]],
) -> Result<(), 大気数学エラー> {
    for (横, 縦) in 透過率の代表 {
        let 期待 = 透過率のベイク済み画像のテクセル値(媒体.消散(), 解像度, 横, 縦)?.成分();
        let 実測 = テクセルを参照する(読み戻し, 解像度.透過率の幅(), 横, 縦);
        代表行を出す("透過率代表", 横, 縦, 期待, 実測);
    }
    Ok(())
}

pub(super) fn 多重散乱の代表テクセルを出す(
    媒体: &大気散乱媒体,
    透過率表: &透過率表,
    解像度: 大気のベイク済み画像の解像度,
    読み戻し: &[[f32; 4]],
) -> Result<(), 大気数学エラー> {
    for (横, 縦) in 多重散乱の代表 {
        let 期待 = 多重散乱のベイク済み画像のテクセル値(媒体, 透過率表, 解像度, 横, 縦)?.成分();
        let 実測 = テクセルを参照する(読み戻し, 解像度.多重散乱の一辺(), 横, 縦);
        代表行を出す("多重散乱代表", 横, 縦, 期待, 実測);
    }
    Ok(())
}

/// スカイビューの代表テクセルを出すのに要る材料。引数の列が伸びるのを避けて1つに束ねる。
pub(super) struct スカイビューの材料<'a> {
    pub(super) 媒体: &'a 大気散乱媒体,
    pub(super) 透過率表: &'a 透過率表,
    pub(super) 多重散乱表: &'a 多重散乱表,
    pub(super) 解像度: 大気のベイク済み画像の解像度,
    pub(super) 観測条件: スカイビュー観測条件,
    pub(super) 読み戻し: &'a [[f32; 4]],
}

pub(super) fn スカイビューの代表テクセルを出す(材料: スカイビューの材料<'_>) -> Result<(), 大気数学エラー> {
    for (横, 縦) in スカイビューの代表 {
        let 期待 = スカイビューのベイク済み画像のテクセル値(
            材料.媒体,
            材料.透過率表,
            材料.多重散乱表,
            材料.解像度,
            材料.観測条件,
            横,
            縦,
        )?
        .成分();
        let 実測 = テクセルを参照する(材料.読み戻し, 材料.解像度.スカイビューの幅(), 横, 縦);
        代表行を出す("スカイビュー代表", 横, 縦, 期待, 実測);
    }
    Ok(())
}

fn テクセルを参照する(読み戻し: &[[f32; 4]], 幅: u32, 横: u32, 縦: u32) -> [f32; 3] {
    let 幅 = usize::try_from(幅).unwrap_or(0);
    let 横 = usize::try_from(横).unwrap_or(0);
    let 縦 = usize::try_from(縦).unwrap_or(0);
    let Some(テクセル) = 読み戻し.get(縦 * 幅 + 横) else {
        panic!("読み戻しの範囲外を参照した(横{横} 縦{縦})。代表テクセルの座標が解像度と食い違っている");
    };
    [テクセル[0], テクセル[1], テクセル[2]]
}
