//! 代表テクセルの1行ずつの報告と、2回焼いた結果の突き合わせ。
//! 受け取るのは読み戻した生の4成分とCPU正本の材料、返す代わりに行を標準出力へ出す。
//!
//! 代表テクセルを選ぶのは、全テクセルのCPU正本を出すと多重散乱の計算量が検収の時間に見合わないためである。
//! 端・中央・地平線付近という写像の性質が変わる位置を選び、全体の健全性は統計の行が受け持つ。

use blitz_render::atmosphere::{
    多重散乱lutのテクセル値, 大気LUT解像度, 大気散乱媒体, 大気数学エラー, 透過率lutのテクセル値, 透過率表
};
use blitz_render::atmosphere_lut_probe::大気LUT読み戻し;

/// 透過率LUTの代表テクセル。左端・中央・右端をそれぞれ地表付近と高高度で見る。
const 透過率の代表: [(u32, u32); 6] = [(0, 0), (128, 0), (255, 0), (0, 32), (128, 32), (255, 63)];
/// 多重散乱LUTの代表テクセル。太陽が真下・水平・真上の3つを地表付近と高高度で見る。
const 多重散乱の代表: [(u32, u32); 6] = [(0, 0), (16, 0), (31, 0), (0, 16), (16, 16), (31, 31)];

/// validation層の在否と、2回の実行が数えた指摘の合計。件数を合計で出すのは、どちらの実行で出た指摘も
/// 同じ1つの検収を落とすべきだからである。層が無い実行の0件を有効な実行の0件と読み違えないよう、状況も同じ行へ出す。
pub(super) fn 検証を出す(一回目: &大気LUT読み戻し, 二回目: &大気LUT読み戻し) {
    println!(
        "検証層 状況={} 件数={}",
        一回目.検証層の状況().呼び名(),
        一回目.検証件数() + 二回目.検証件数()
    );
}

pub(super) fn 再現性を出す(一回目: &大気LUT読み戻し, 二回目: &大気LUT読み戻し) {
    println!(
        "再現性 透過率の不一致={} 多重散乱の不一致={}",
        不一致数(一回目.透過率(), 二回目.透過率()),
        不一致数(一回目.多重散乱(), 二回目.多重散乱())
    );
}

pub(super) fn 透過率の代表テクセルを出す(
    媒体: &大気散乱媒体,
    解像度: 大気LUT解像度,
    読み戻し: &[[f32; 4]],
) -> Result<(), 大気数学エラー> {
    for (横, 縦) in 透過率の代表 {
        let 期待 = 透過率lutのテクセル値(媒体.消散(), 解像度, 横, 縦)?.成分();
        let 実測 = テクセルを引く(読み戻し, 解像度.透過率の幅(), 横, 縦);
        代表行を出す("透過率代表", 横, 縦, 期待, 実測);
    }
    Ok(())
}

pub(super) fn 多重散乱の代表テクセルを出す(
    媒体: &大気散乱媒体,
    透過率表: &透過率表,
    解像度: 大気LUT解像度,
    読み戻し: &[[f32; 4]],
) -> Result<(), 大気数学エラー> {
    for (横, 縦) in 多重散乱の代表 {
        let 期待 = 多重散乱lutのテクセル値(媒体, 透過率表, 解像度, 横, 縦)?.成分();
        let 実測 = テクセルを引く(読み戻し, 解像度.多重散乱の一辺(), 横, 縦);
        代表行を出す("多重散乱代表", 横, 縦, 期待, 実測);
    }
    Ok(())
}

fn 代表行を出す(見出し: &str, 横: u32, 縦: u32, 期待: [f32; 3], 実測: [f32; 3]) {
    println!(
        "{見出し} 横={横} 縦={縦} 期待赤={:.9} 期待緑={:.9} 期待青={:.9} 実測赤={:.9} 実測緑={:.9} 実測青={:.9}",
        期待[0], 期待[1], 期待[2], 実測[0], 実測[1], 実測[2]
    );
}

fn テクセルを引く(読み戻し: &[[f32; 4]], 幅: u32, 横: u32, 縦: u32) -> [f32; 3] {
    let 幅 = usize::try_from(幅).unwrap_or(0);
    let 横 = usize::try_from(横).unwrap_or(0);
    let 縦 = usize::try_from(縦).unwrap_or(0);
    let Some(テクセル) = 読み戻し.get(縦 * 幅 + 横) else {
        panic!("読み戻しの範囲外を引いた(横{横} 縦{縦})。代表テクセルの座標が解像度と食い違っている");
    };
    [テクセル[0], テクセル[1], テクセル[2]]
}

/// 2回の読み戻しを1ビットも違わないかで比べる。丸めの許容を持たないのは、決定性の契約が完全一致だからである。
fn 不一致数(一回目: &[[f32; 4]], 二回目: &[[f32; 4]]) -> usize {
    if 一回目.len() != 二回目.len() {
        return 一回目.len().max(二回目.len());
    }
    一回目
        .iter()
        .zip(二回目)
        .filter(|(左, 右)| 左.iter().zip(右.iter()).any(|(左値, 右値)| 左値.to_bits() != 右値.to_bits()))
        .count()
}
