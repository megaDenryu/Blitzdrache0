//! 空中遠近ボリュームの代表ボクセルの選び方と、その1ボクセルずつの報告。
//! 受け取るのは読み戻した生の4成分とCPU正本の材料、返す代わりに行を標準出力へ出す。
//!
//! 平面のベイク済み画像と別に持つのは、参照する添字が3次元であり、4成分目が予約でなく代表透過率だからである。
//! 代表透過率は散乱と許容の見方が違うため、散乱3成分の行とは別の行として出す。

use blitz_render::atmosphere::{大気数学エラー, 空中遠近ボリュームのボクセル値, 空中遠近ボリュームの材料};

use super::representative_line::代表行を出す;

/// 空中遠近ボリュームの代表ボクセル。近(1)・中(79)・遠(159)の3つの距離を、画面の横の端と中央で見る。
/// 距離0のスライスは値が厳密に0と1であり誤差を持たないため代表に選ばない(値域と境界はユニットテストが見る)。
///
/// 縦を8(視線が水平から上を向く行)に取るのは、CPU正本を期待値として使える範囲がそこだからである。
/// 媒体の規格化密度は高度0で1から0へ跳ぶ(地表より下は密度分布の第1層が空の層である)。惑星半径6.36e6メートルを
/// f32で扱うGPUは半径を0.5メートルの刻みでしか表せないため、標本点の高度が0の近くに並ぶ視線では標本ごとに
/// 跳びのどちら側かが反転する。水平から3度下を向く視線は1区間8メートルあたり高度が0.25メートルしか下がらず、
/// 刻みより細かいためこの反転が数点まとめて起きる。実測ではCPUのf64に対して散乱が16パーセント食い違った。
/// 下を向く視線はどれだけ急でも代表に使えない。観測高度が1.5メートルであるため、最初の標本点が必ず跳びから
/// 数メートル以内に入り、そこで反転が起きる(実測では急な下向きの縦31でCPUの0に対しGPUが5.2e-6を返した)。
/// 地平線をかすめる上向き(縦15)は高度が上がる一方であり跳びをまたがないため、地平線付近の条件はそちらで覆う。
///
/// 反転が起きる領域を合成が読まないことがこの選び方の根拠である。地形が理想球の上にある限り、視線が地形へ当たる
/// 距離までの標本点の高度はすべて0以上であり、跳びをまたぐのは地形より遠いスライスだけである。
/// 全ボクセルの有限性・非負・透過率の値域は統計の行がこの領域も含めて見る。
const 空中遠近の代表: [(u32, u32, u32); 6] = [(16, 8, 1), (16, 8, 79), (16, 8, 159), (0, 8, 79), (31, 8, 159), (16, 15, 159)];

pub(super) fn 空中遠近の代表ボクセルを出す(
    材料: 空中遠近ボリュームの材料<'_>,
    読み戻し: &[[f32; 4]],
) -> Result<(), 大気数学エラー> {
    let 幅 = 材料.解像度.空中遠近の幅();
    let 高さ = 材料.解像度.空中遠近の高さ();
    for (横, 縦, 奥) in 空中遠近の代表 {
        let 期待 = 空中遠近ボリュームのボクセル値(材料, 横, 縦, 奥)?;
        let 実測 = ボクセルを参照する(読み戻し, 幅, 高さ, 横, 縦, 奥);
        代表行を出す("空中遠近代表", 横, 縦, 期待.散乱の成分(), [実測[0], 実測[1], 実測[2]]);
        println!("空中遠近透過率 横={横} 縦={縦} 奥={奥} 期待={:.9} 実測={:.9}", 期待.代表透過率(), 実測[3]);
    }
    Ok(())
}

fn ボクセルを参照する(読み戻し: &[[f32; 4]], 幅: u32, 高さ: u32, 横: u32, 縦: u32, 奥: u32) -> [f32; 4] {
    let (幅, 高さ) = (usize::try_from(幅).unwrap_or(0), usize::try_from(高さ).unwrap_or(0));
    let 添字 = usize::try_from(奥).unwrap_or(0) * 幅 * 高さ + usize::try_from(縦).unwrap_or(0) * 幅 + usize::try_from(横).unwrap_or(0);
    let Some(ボクセル) = 読み戻し.get(添字) else {
        panic!("読み戻しの範囲外を参照した(横{横} 縦{縦} 奥{奥})。代表ボクセルの座標が解像度と食い違っている");
    };
    *ボクセル
}
