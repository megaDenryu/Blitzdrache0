//! `--report-streaming-summary`指定時の終了時出力。運んだ量は起動からの累計、使用量は各フレームで台帳が導出した値の最大である。
//! 呼び出しタイミング: 実行の終わりに1回だけ呼ぶ。毎フレーム呼ぶ`streaming`の進行表示とは入力も頻度も異なる。

use crate::app::ストリーミング要約;

pub(crate) fn 表示する(要約: &ストリーミング要約) {
    println!("ストリーミング要約:");
    println!("  観測フレーム数: {}", 要約.観測フレーム数);
    println!("  縮退フレーム数: {}", 要約.縮退フレーム数);
    println!(
        "  ディスク読込: {}件 / {} bytes",
        要約.転送量.ディスク読込件数(),
        要約.転送量.ディスク読込バイト数()
    );
    println!(
        "  GPU転送: {}件 / {} bytes(見積)",
        要約.転送量.gpu転送件数(),
        要約.転送量.gpu転送バイト数()
    );
    println!("  GPU資源解除: {}件", 要約.転送量.gpu解除件数());
    println!("  上限: RAM {} bytes / VRAM {} bytes", 要約.上限.ramバイト数, 要約.上限.vramバイト数);
    println!(
        "  最大使用量: RAM {} bytes / VRAM {} bytes",
        要約.最大使用量.ramバイト数, 要約.最大使用量.vramバイト数
    );
    println!("  最大台帳登録数: {}", 要約.最大台帳登録数);
    println!("  見送りフレーム数: {}", 要約.見送りフレーム数);
    処理時間を表示する(要約);
}

/// 調停と描画束の追加解除がメインスレッドを占めた時間。フレーム間隔の計測とは別の量であり、混同しないよう区間名を明示する。
fn 処理時間を表示する(要約: &ストリーミング要約) {
    let Some(統計) = &要約.処理時間統計 else {
        println!("  ストリーミング処理時間: 計測できなかった(ウォームアップ後のフレームがない)");
        return;
    };
    println!("  ストリーミング処理時間(調停+描画束の追加解除、先頭120フレーム除外):");
    println!("    標本数: {}", 統計.標本数);
    println!("    平均: {:.4} ms", 統計.平均ms);
    println!("    p50: {:.4} ms", 統計.p50ms);
    println!("    p95: {:.4} ms", 統計.p95ms);
    println!("    p99: {:.4} ms", 統計.p99ms);
    println!("    最大: {:.4} ms", 統計.最大ms);
}
