//! 反射率積分表の代表テクセルとCPU正本との突き合わせ。受け取るのは読み戻しと解像度、
//! 返す代わりに四隅と中央の5テクセルの行を標準出力へ出す。
//!
//! 四隅を見るのは、視線が面に近い側と垂直な側、粗さが0に近い側と1に近い側という4つの端の組で
//! 遮蔽項と標本の密度の扱いが最も違うためである。中央は端でない代表として足す。

use blitz_render::distant_environment::derived::{反射率積分表のテクセル値, 反射率積分表の解像度};
use blitz_render::distant_environment::derived_probe::派生表現の読み戻し;

use super::report_error::派生表現報告エラー;

pub(super) fn 反射率積分表の代表を出す(
    読み戻し: &派生表現の読み戻し,
    解像度: 反射率積分表の解像度,
) -> Result<(), 派生表現報告エラー> {
    let 端の横 = 解像度.横() - 1;
    let 端の縦 = 解像度.縦() - 1;
    let 見る位置 = [(0, 0), (端の横, 0), (0, 端の縦), (端の横, 端の縦), (解像度.横() / 2, 解像度.縦() / 2)];
    for (横, 縦) in 見る位置 {
        let 期待 = 反射率積分表のテクセル値(解像度, 横, 縦)?;
        let 実測 = テクセルを参照する(読み戻し.反射率積分表(), 解像度, 横, 縦);
        println!(
            "反射率積分表代表 横={横} 縦={縦} 期待倍率={:.9} 期待加算={:.9} 実測倍率={:.9} 実測加算={:.9}",
            期待[0], 期待[1], 実測[0], 実測[1]
        );
    }
    Ok(())
}

fn テクセルを参照する(読み戻し: &[[f32; 2]], 解像度: 反射率積分表の解像度, 横: u32, 縦: u32) -> [f32; 2] {
    let 横添字 = usize::try_from(横).unwrap_or(0);
    let 縦添字 = usize::try_from(縦).unwrap_or(0);
    let 幅 = usize::try_from(解像度.横()).unwrap_or(0);
    let Some(テクセル) = 読み戻し.get(縦添字 * 幅 + 横添字) else {
        panic!("反射率積分表の読み戻しの範囲外を参照した(横{横} 縦{縦})");
    };
    *テクセル
}
