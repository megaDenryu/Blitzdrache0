//! 鏡面畳込みの読み戻しを粗さ段ごとに切り分ける工程。受け取るのは全段ぶんの列と解像度、返すのは段の区間である。
//!
//! 段ごとに寸法が違うため、通し番号だけでは段の境目が分からない。切り分けの規則を1箇所に置くのは、
//! 統計・面境界・代表テクセルの3つが同じ切り分けを要るためである。

use blitz_render::distant_environment::derived::{粗さ段, 鏡面畳込みの解像度};

/// 指定の段のテクセルだけを取り出す。並びは面(層番号の順)・縦・横の順である。
pub(super) fn 段の区間(読み戻し: &[[f32; 4]], 解像度: 鏡面畳込みの解像度, 段: 粗さ段) -> &[[f32; 4]] {
    let 開始: usize = 解像度
        .全段()
        .into_iter()
        .filter(|前の段| 前の段.番号() < 段.番号())
        .map(|前の段| 解像度.段の一辺(前の段).全テクセル数())
        .sum();
    let 長さ = 解像度.段の一辺(段).全テクセル数();
    let Some(区間) = 読み戻し.get(開始..開始 + 長さ) else {
        panic!(
            "鏡面畳込みの読み戻しが段{}の区間を含まない(読み戻しの容量と解像度が食い違っている)",
            段.番号()
        );
    };
    区間
}
