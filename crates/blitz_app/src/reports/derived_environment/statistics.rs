//! 派生表現の全テクセルの統計。受け取るのは種別の名前と読み戻した生の成分、返す代わりに1行の統計を標準出力へ出す。
//!
//! 破れの件数を出すのは、代表テクセルの一致だけでは面の角や境界の壊れた値を見逃すためである。
//! 立方体の4成分目はシェーダーが予約として0を書くことをここが確かめる。

pub(super) fn 立方体の統計を出す(種別: &str, テクセル一覧: &[[f32; 4]]) {
    let mut 非有限 = 0_usize;
    let mut 負 = 0_usize;
    let mut 予約が非零 = 0_usize;
    for テクセル in テクセル一覧 {
        破れを数える(&テクセル[0..3], &mut 非有限, &mut 負);
        if テクセル[3] != 0.0 {
            予約が非零 += 1;
        }
    }
    println!(
        "派生表現統計 種別={種別} テクセル数={} 非有限={非有限} 負={負} 予約が非零={予約が非零}",
        テクセル一覧.len()
    );
}

pub(super) fn 表の統計を出す(テクセル一覧: &[[f32; 2]]) {
    let mut 非有限 = 0_usize;
    let mut 負 = 0_usize;
    for テクセル in テクセル一覧 {
        破れを数える(テクセル, &mut 非有限, &mut 負);
    }
    println!(
        "派生表現統計 種別=反射率積分表 テクセル数={} 非有限={非有限} 負={負} 予約が非零=0",
        テクセル一覧.len()
    );
}

fn 破れを数える(成分一覧: &[f32], 非有限: &mut usize, 負: &mut usize) {
    for 値 in 成分一覧 {
        if !値.is_finite() {
            *非有限 += 1;
            continue;
        }
        if *値 < 0.0 {
            *負 += 1;
        }
    }
}
