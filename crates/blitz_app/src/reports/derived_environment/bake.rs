//! 与えた遠方環境の上で派生表現を1回焼いて読み戻す工程。受け取るのは遠方環境の内容、返すのは読み戻しである。
//!
//! 解像度をここが決めるのは、CPU正本の期待値を求める側と焼く側が必ず同じ解像度を使うためである。
//! 2箇所で別々に既定値を読むと、片方だけ解像度を変えたときに検査が一致しない理由を説明できなくなる。

use blitz_render::distant_environment::derived::{
    反射率積分表の解像度, 拡散照度の解像度, 遠方環境の内容, 鏡面畳込みの解像度
};
use blitz_render::distant_environment::derived_probe::{
    派生表現の焼き上げ条件, 派生表現の読み戻し, 派生表現をgpuで焼いて読み戻す
};

use super::report_error::派生表現報告エラー;

/// 検査に使う3つの解像度。既定値をそのまま採るのは、本番が焼くのと同じ寸法で判定するためである。
#[derive(Clone, Copy)]
pub(super) struct 検査する解像度 {
    pub(super) 拡散照度: 拡散照度の解像度,
    pub(super) 鏡面畳込み: 鏡面畳込みの解像度,
    pub(super) 反射率積分表: 反射率積分表の解像度,
}

impl 検査する解像度 {
    pub(super) fn 既定値() -> Self {
        Self {
            拡散照度: 拡散照度の解像度::既定値(),
            鏡面畳込み: 鏡面畳込みの解像度::既定値(),
            反射率積分表: 反射率積分表の解像度::既定値(),
        }
    }
}

pub(super) fn 焼く(
    環境: &遠方環境の内容, 解像度: 検査する解像度
) -> Result<派生表現の読み戻し, 派生表現報告エラー> {
    let シェーダー = crate::embedded_derived_environment_shaders::埋め込み派生表現シェーダーを生成する()?;
    Ok(派生表現をgpuで焼いて読み戻す(派生表現の焼き上げ条件 {
        遠方環境: 環境,
        拡散照度の解像度: 解像度.拡散照度,
        鏡面畳込みの解像度: 解像度.鏡面畳込み,
        反射率積分表の解像度: 解像度.反射率積分表,
        拡散照度のシェーダー: &シェーダー.拡散照度,
        鏡面畳込みのシェーダー: &シェーダー.鏡面畳込み,
        反射率積分表のシェーダー: &シェーダー.反射率積分表,
    })?)
}
