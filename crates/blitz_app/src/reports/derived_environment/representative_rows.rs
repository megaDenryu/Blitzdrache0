//! 派生表現の代表テクセルとCPU正本との突き合わせ。受け取るのは遠方環境の内容と読み戻しと解像度、
//! 返す代わりに1テクセルずつの行を標準出力へ出す。
//!
//! 代表テクセルを選ぶのは、全テクセルのCPU正本を求めると標本数×テクセル数の畳み込みが検収の時間に見合わないためである。
//! 面の中心と角という写像の性質が変わる位置を全6面で選び、全体の健全性は統計の行が受け持つ。
//!
//! CPU正本へ半精度へ丸めた環境を渡すのは、GPUの画像が半精度で入力を保つためである。丸めをそろえないと、
//! 写しの誤りでない差が最初から乗る。

use blitz_render::atmosphere::立方体の全面;
use blitz_render::distant_environment::derived::{拡散照度のテクセル値, 遠方環境の内容, 鏡面畳込みのテクセル値};
use blitz_render::distant_environment::derived_probe::派生表現の読み戻し;

use super::bake::検査する解像度;
use super::slices::段の区間;
use crate::reports::cube_seam::texel_access::立方体のテクセル;

/// 面内で見る2つの位置の割り当て方。中心と左上の角である。
const 面内の代表: [(bool, bool); 2] = [(true, true), (false, false)];

pub(super) fn 代表テクセルを出す(
    環境: &遠方環境の内容, 読み戻し: &派生表現の読み戻し, 解像度: 検査する解像度
) {
    let 一辺 = 解像度.拡散照度.面の一辺().値();
    for 面 in 立方体の全面 {
        for (横は中央, 縦は中央) in 面内の代表 {
            let (横, 縦) = (添字(横は中央, 一辺), 添字(縦は中央, 一辺));
            let 期待 = 拡散照度のテクセル値(環境, 解像度.拡散照度, 面, 横, 縦);
            let 実測 = 立方体のテクセル(読み戻し.拡散照度(), 面, 横, 縦, 一辺);
            行を出す("拡散", 0, 面.層番号(), 横, 縦, 期待, 実測);
        }
    }
    鏡面の代表を出す(環境, 読み戻し, 解像度);
}

fn 鏡面の代表を出す(環境: &遠方環境の内容, 読み戻し: &派生表現の読み戻し, 解像度: 検査する解像度) {
    for 段 in 解像度.鏡面畳込み.全段() {
        let 一辺 = 解像度.鏡面畳込み.段の一辺(段).値();
        let 区間 = 段の区間(読み戻し.鏡面畳込み(), 解像度.鏡面畳込み, 段);
        for 面 in 立方体の全面 {
            for (横は中央, 縦は中央) in 面内の代表 {
                let (横, 縦) = (添字(横は中央, 一辺), 添字(縦は中央, 一辺));
                let 期待 = 鏡面畳込みのテクセル値(環境, 解像度.鏡面畳込み, 段, 面, 横, 縦);
                let 実測 = 立方体のテクセル(区間, 面, 横, 縦, 一辺);
                行を出す("鏡面", 段.番号(), 面.層番号(), 横, 縦, 期待, 実測);
            }
        }
    }
}

/// 割合でなく端と中央の名前で位置を持つのは、実数から添字への丸めを避けるためである。
fn 添字(中央か: bool, 一辺: u32) -> u32 {
    if 中央か { 一辺 / 2 } else { 0 }
}

fn 行を出す(種別: &str, 段: u32, 層: u32, 横: u32, 縦: u32, 期待: [f64; 3], 実測: [f32; 3]) {
    println!(
        "派生表現代表 種別={種別} 段={段} 層={層} 横={横} 縦={縦} 期待赤={:.9} 期待緑={:.9} 期待青={:.9} 実測赤={:.9} 実測緑={:.9} 実測青={:.9}",
        期待[0], 期待[1], 期待[2], 実測[0], 実測[1], 実測[2]
    );
}
