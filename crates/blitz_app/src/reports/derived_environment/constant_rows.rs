//! 定数の遠方環境を入れたときの解析解との突き合わせ。受け取るのは読み戻しと入れた放射輝度、
//! 返す代わりに拡散と鏡面の最大相対誤差を1行ずつ標準出力へ出す。
//!
//! これが畳み込みの重みの規約が正しいことの証拠である。重みの正規化を誤ると、環境が一様でも結果が
//! 放射輝度の定数倍だけずれ、絵では明るさの違いにしか見えない。

use std::f64::consts::PI;

use blitz_render::distant_environment::derived_probe::派生表現の読み戻し;

use super::bake::検査する解像度;
use super::slices::段の区間;

pub(super) fn 定数環境の判定を出す(読み戻し: &派生表現の読み戻し, 解像度: 検査する解像度, 放射輝度: [f64; 3]) {
    let 期待する照度 = [PI * 放射輝度[0], PI * 放射輝度[1], PI * 放射輝度[2]];
    println!(
        "定数環境拡散 放射輝度緑={:.9} 最大相対誤差={:.9}",
        放射輝度[1],
        最大相対誤差(読み戻し.拡散照度(), 期待する照度)
    );
    for 段 in 解像度.鏡面畳込み.全段() {
        println!(
            "定数環境鏡面 放射輝度緑={:.9} 段={} 最大相対誤差={:.9}",
            放射輝度[1],
            段.番号(),
            最大相対誤差(段の区間(読み戻し.鏡面畳込み(), 解像度.鏡面畳込み, 段), 放射輝度)
        );
    }
}

/// 全テクセルの全成分を1つの期待値と突き合わせ、相対誤差の最大を返す。
/// 期待値が0に近い成分では相対誤差が発散するため、分母に下限を置いて絶対差の扱いへ落とす。
fn 最大相対誤差(テクセル一覧: &[[f32; 4]], 期待: [f64; 3]) -> f64 {
    let mut 最大 = 0.0_f64;
    for テクセル in テクセル一覧 {
        for 添字 in 0..3 {
            let 実測 = f64::from(テクセル[添字]);
            最大 = 最大.max((実測 - 期待[添字]).abs() / 期待[添字].abs().max(1.0e-6));
        }
    }
    最大
}
