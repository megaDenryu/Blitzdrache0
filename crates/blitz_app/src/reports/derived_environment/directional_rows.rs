//! 方向性の強い遠方環境を入れたときの性質の報告。受け取るのは読み戻しと解像度、返す代わりに段ごとのばらつき・
//! 最詳細段の一致・面境界の連続性を標準出力へ出す。
//!
//! ばらつきの単調な減りは、粗さが標本の広がりへ効いていることの証拠である。粗さを読み落とすとどの段も同じ画像になり、
//! 絵では「反射がぼけない」という形でしか現れない。最詳細段の一致は複製がビット単位で行われたことの証拠である。

use blitz_render::distant_environment::derived_probe::派生表現の読み戻し;

use super::bake::検査する解像度;
use super::slices::段の区間;
use crate::reports::cube_seam::面境界を突き合わせる;

pub(super) fn 方向性の判定を出す(読み戻し: &派生表現の読み戻し, 解像度: 検査する解像度) {
    for 段 in 解像度.鏡面畳込み.全段() {
        let 区間 = 段の区間(読み戻し.鏡面畳込み(), 解像度.鏡面畳込み, 段);
        println!("鏡面段ばらつき 段={} 分散={:.9}", 段.番号(), 緑成分の分散(区間));
        let 一辺 = 解像度.鏡面畳込み.段の一辺(段).値();
        let 観測 = 面境界を突き合わせる(区間, 一辺);
        println!(
            "派生表現面境界 種別=鏡面 段={} 一辺={一辺} 稜線数={} 最大相対差={:.9}",
            段.番号(),
            観測.稜線数,
            観測.最大相対差
        );
    }
    let 最詳細段 = 段の区間(読み戻し.鏡面畳込み(), 解像度.鏡面畳込み, 最詳細段を取る(解像度));
    println!("鏡面最詳細段 不一致={}", 不一致数(読み戻し.遠方環境(), 最詳細段));
    let 拡散の一辺 = 解像度.拡散照度.面の一辺().値();
    let 拡散の観測 = 面境界を突き合わせる(読み戻し.拡散照度(), 拡散の一辺);
    println!(
        "派生表現面境界 種別=拡散 段=0 一辺={拡散の一辺} 稜線数={} 最大相対差={:.9}",
        拡散の観測.稜線数, 拡散の観測.最大相対差
    );
}

fn 最詳細段を取る(解像度: 検査する解像度) -> blitz_render::distant_environment::derived::粗さ段 {
    let 全段 = 解像度.鏡面畳込み.全段();
    let Some(&段) = 全段.first() else {
        panic!("鏡面畳込みの解像度が段を1つも持たない");
    };
    段
}

/// 2つの列を1ビットも違わないかで比べる。丸めの許容を持たないのは、最詳細段が画像どうしの複製だからである。
fn 不一致数(遠方環境: &[[f32; 4]], 最詳細段: &[[f32; 4]]) -> usize {
    if 遠方環境.len() != 最詳細段.len() {
        return 遠方環境.len().max(最詳細段.len());
    }
    遠方環境
        .iter()
        .zip(最詳細段)
        .filter(|(左, 右)| 左.iter().zip(右.iter()).any(|(左値, 右値)| 左値.to_bits() != 右値.to_bits()))
        .count()
}

fn 緑成分の分散(テクセル一覧: &[[f32; 4]]) -> f64 {
    let 件数 = f64::from(u32::try_from(テクセル一覧.len()).unwrap_or(1));
    let 平均 = テクセル一覧.iter().map(|テクセル| f64::from(テクセル[1])).sum::<f64>() / 件数;
    テクセル一覧
        .iter()
        .map(|テクセル| (f64::from(テクセル[1]) - 平均) * (f64::from(テクセル[1]) - 平均))
        .sum::<f64>()
        / 件数
}
