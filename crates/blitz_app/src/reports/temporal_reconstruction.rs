//! 時間再構成の観測をコンソールへ出す報告。担うのは3種の行を組むことだけであり、期待値も合否も持たない。
//!
//! 合否をここが持たないのは、静止カメラでの安定化がまだ判定値を持たない観測だからである。画素内ずらしが回り続けるため
//! 定常状態は1つの絵へ止まる不動点でなく、列の長さを周期とする周期軌道になる。閾値は実測からオーナーが制定する
//! (`参照: _doc/設計/時間再構成.md`「検収戦略(判断g)」の3)。突き合わせは`cargo xtask temporal-reconstruction`が行う。

mod difference;
mod digest;

use blitz_render::HDR読み戻し画像;

/// 要約行の見出し。`cargo xtask temporal-reconstruction`はこの語で行を拾う。
const 見出し: &str = "[temporal-reconstruction]";

/// 静止カメラで隣り合う2フレームの差。周期軌道の中でどれだけ絵が揺れているかを表す。
pub(crate) fn フレーム間差分を報告する(フレーム番号: u32, 前: &HDR読み戻し画像, 今: &HDR読み戻し画像) {
    let 差 = difference::求める(前, 今);
    println!("{見出し} フレーム間差分 フレーム{フレーム番号}、最大{:.9}、平均{:.9}", 差.最大, 差.平均);
}

/// 履歴を無効にした直後の1フレーム目の結果と、そのフレームの今の色の突き合わせ。判断cの規律を画素で反証する。
pub(crate) fn 無効化直後を報告する(再構成後: &HDR読み戻し画像, 今のフレームの色: &HDR読み戻し画像) {
    let 差 = difference::求める(再構成後, 今のフレームの色);
    println!(
        "{見出し} 無効化直後 全画素{}、最大差{:.9}、一致しない画素{}",
        再構成後.成分列().len() / 4,
        差.最大,
        差.一致しない画素数
    );
}

/// 再構成後の画像そのものの要約値。同じ条件の2実行がこの値で一致することが、起動モードの契約の下での決定性である。
pub(crate) fn 要約を報告する(再構成後: &HDR読み戻し画像) {
    println!("{見出し} 要約 ダイジェスト{:016x}", digest::求める(再構成後));
}

pub(crate) fn 見送りを報告する(局面: &str, 理由: &str) {
    println!("{見出し} 読み戻しを見送った({局面}): {理由}");
}
