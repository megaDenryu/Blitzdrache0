//! 太陽天頂区間の跨ぎ報告が途中で止まる原因。描画を伴わない報告のため起動エラーへは合流させず、この報告の中で閉じる。

use blitz_engine::sky::天空状態エラー;
use thiserror::Error;

#[derive(Debug, Error)]
pub(super) enum 跨ぎ報告エラー {
    #[error("空ありの既定が空なしを返した")]
    空ありの既定が空なしを返した,

    #[error("いちばん下の区間に下側の区間が無い")]
    いちばん下の区間に下側が無い,

    #[error("跨ぎの列挙か区間の作り直しが成立しなかった: {0}")]
    天空状態が導けない(#[from] 天空状態エラー),
}
