//! 大気のベイク済み画像のGPU読み戻し報告。ウィンドウもスワップチェーンも作らず、ウィンドウなし実行のGPUで3枚のベイク済み画像を焼いて読み戻し、
//! CPU正本との差と全体の統計を機械可読な行として標準出力へ出す。
//! これが大気のベイク済み画像生成シェーダーの本番外の呼び出し元であり、判定は`cargo xtask atmosphere-lut`がこの出力を読んで行う。
//!
//! 同じ入力で2回焼いて突き合わせるのは、決定性の契約(同一GPU実装・同一入力で同一出力)を確かめるためである。

mod aerial_condition;
mod aerial_rows;
mod aerial_statistics;
mod component_counts;
mod report_error;
mod representative_line;
mod rows;
mod run_rows;
mod statistics;
use blitz_engine::sky::atmosphere::大気媒体方針;
use blitz_engine::sky::空描画方針;
use blitz_render::atmosphere::{
    スカイビュー観測条件, 多重散乱表, 大気のベイク済み画像の解像度, 天頂余弦, 空中遠近ボリュームの材料, 透過率表
};
use report_error::大気のベイク済み画像報告エラー;
use std::process::ExitCode;
/// 検査に使う太陽の天頂余弦。60度の高度に相当し、太陽が地平線より十分上で全テクセルに散乱の寄与がある条件である。
/// 端の条件(真上・地平線・地平線下)は代表テクセルの縦横で覆う。
const 検査する太陽天頂余弦: f32 = 0.866_025_4;
pub(crate) fn 大気のベイク済み画像表を出す() -> ExitCode {
    match 報告する() {
        Ok(()) => ExitCode::SUCCESS,
        Err(誤り) => {
            eprintln!("大気のベイク済み画像報告に失敗した: {誤り}");
            ExitCode::FAILURE
        }
    }
}
fn 報告する() -> Result<(), 大気のベイク済み画像報告エラー> {
    let シェーダー = crate::embedded_shaders::埋め込み大気のベイク済み画像シェーダーを生成する()?;
    let 媒体 = crate::atmosphere_medium::大気散乱媒体へ写す(&大気媒体方針::地球標準())?;
    let 解像度 = 大気のベイク済み画像の解像度::既定値();
    let 観測高度 = 空描画方針::既定値().観測高度();
    let 観測条件 = スカイビュー観測条件::生成する(観測高度, 天頂余弦::生成する(検査する太陽天頂余弦)?)?;
    let 空中遠近条件 = aerial_condition::空中遠近の観測条件を組み立てる(観測高度, 検査する太陽天頂余弦)?;
    println!(
        "大気のベイク済み画像報告 透過率幅={} 透過率高さ={} 多重散乱一辺={} スカイビュー幅={} スカイビュー高さ={} 空中遠近幅={} 空中遠近高さ={} 空中遠近奥行き={} 観測高度={} 太陽天頂余弦={} 空中遠近最遠距離={}",
        解像度.透過率の幅(),
        解像度.透過率の高さ(),
        解像度.多重散乱の一辺(),
        解像度.スカイビューの幅(),
        解像度.スカイビューの高さ(),
        解像度.空中遠近の幅(),
        解像度.空中遠近の高さ(),
        解像度.空中遠近の奥行き(),
        観測条件.観測高度().値(),
        観測条件.太陽天頂余弦().値(),
        空中遠近条件.最遠距離().値()
    );
    let 焼く = || {
        blitz_render::atmosphere_lut_probe::大気のベイク済み画像をgpuで焼いて読み戻す(
            &媒体,
            解像度,
            観測条件,
            空中遠近条件,
            &シェーダー,
        )
    };
    let 一回目 = 焼く()?;
    let 二回目 = 焼く()?;
    run_rows::検証を出す(&一回目, &二回目);
    run_rows::再現性を出す(&一回目, &二回目);
    let 透過率表 = 透過率表::焼く(媒体.消散(), 解像度)?;
    let 多重散乱表 = 多重散乱表::焼く(&媒体, &透過率表, 解像度)?;
    statistics::透過率の統計を出す(一回目.透過率());
    rows::透過率の代表テクセルを出す(&媒体, 解像度, 一回目.透過率())?;
    statistics::多重散乱の統計を出す(一回目.多重散乱());
    rows::多重散乱の代表テクセルを出す(&媒体, &透過率表, 解像度, 一回目.多重散乱())?;
    statistics::スカイビューの統計を出す(一回目.スカイビュー());
    rows::スカイビューの代表テクセルを出す(rows::スカイビューの材料 {
        媒体: &媒体,
        透過率表: &透過率表,
        多重散乱表: &多重散乱表,
        解像度,
        観測条件,
        読み戻し: 一回目.スカイビュー(),
    })?;
    aerial_statistics::空中遠近の統計を出す(一回目.空中遠近());
    aerial_rows::空中遠近の代表ボクセルを出す(
        空中遠近ボリュームの材料 {
            媒体: &媒体,
            透過率表: &透過率表,
            多重散乱表: &多重散乱表,
            解像度,
            条件: 空中遠近条件,
        },
        一回目.空中遠近(),
    )?;
    Ok(())
}
