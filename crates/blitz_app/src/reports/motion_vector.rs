//! 読み戻した動きベクトル画像の要約をコンソールへ出す報告。担うのは、画素ごとの2成分から
//! 「1画素ぶんの正規化装置座標の幅を超えた画素の数」と「大きさの最大」を数え上げて1行に並べることだけである。
//!
//! 期待値も合否もここが持たないのは、判定に使う条件(カメラを止めた実行か、動かした実行か)を決めるのが
//! 呼び出し側の入口だからである。この報告は観測の並びであり、突き合わせは`cargo xtask motion-vector`が行う。
//!
//! 画素の幅を基準に数えるのは、その量が画面の寸法から一意に決まり、制定を要る閾値でないためである。
//! 静止したカメラでは動きベクトルが1画素の幅を超えず、カメラが1フレームで動いた実行では大きく超える。

use blitz_render::動きベクトル読み戻し画像;

/// 要約行の見出し。`cargo xtask motion-vector`はこの語で行を拾う。
const 見出し: &str = "[motion-vector]";

pub(crate) fn 報告する(画像: &動きベクトル読み戻し画像) {
    let 一画素の幅 = 一画素ぶんの正規化装置座標の幅(画像.幅(), 画像.高さ());
    let 数え上げ = 数え上げる(画像, 一画素の幅);
    let 全画素数 = 画素数(画像);
    println!(
        "{見出し} 全画素{全画素数}、1画素の幅{一画素の幅:.6}を超えた画素{}、非有限画素{}、大きさの最大{:.6}",
        数え上げ.超えた画素数, 数え上げ.非有限画素数, 数え上げ.最大の大きさ
    );
}

pub(crate) fn 見送りを報告する(理由: &str) {
    println!("{見出し} 読み戻しを見送った: {理由}");
}

/// 横と縦のうち短い側の1画素が占める正規化装置座標の幅。正規化装置座標は片側2の広さを持つ。
fn 一画素ぶんの正規化装置座標の幅(幅: u32, 高さ: u32) -> f32 {
    let 長い辺 = 幅.max(高さ).max(1);
    2.0 / f32::from(u16::try_from(長い辺).unwrap_or(u16::MAX))
}

fn 画素数(画像: &動きベクトル読み戻し画像) -> usize {
    画像.正規化装置座標の成分列().len() / 2
}

/// 1度の走査で数え上げる3つの量。
/// 半精度で表せる範囲を超えた値は`非有限画素数`へ現れる。
/// `最大の大きさ`が有限の画素だけを見るのは、非有限を混ぜると最大が常に無限大になり、有限側の分布が読めないためである。
struct 数え上げ {
    超えた画素数: usize,
    非有限画素数: usize, // 2成分のどちらかが非数か無限大である画素の数
    最大の大きさ: f32,   // 有限の画素だけで採った大きさの最大
}

fn 数え上げる(画像: &動きベクトル読み戻し画像, 一画素の幅: f32) -> 数え上げ {
    let mut 結果 = 数え上げ {
        超えた画素数: 0,
        非有限画素数: 0,
        最大の大きさ: 0.0,
    };
    for 対 in 画像.正規化装置座標の成分列().chunks_exact(2) {
        if !対[0].is_finite() || !対[1].is_finite() {
            結果.非有限画素数 += 1;
            結果.超えた画素数 += 1;
            continue;
        }
        let 大きさ = 対[0].hypot(対[1]);
        if 大きさ > 一画素の幅 {
            結果.超えた画素数 += 1;
        }
        結果.最大の大きさ = 結果.最大の大きさ.max(大きさ);
    }
    結果
}
