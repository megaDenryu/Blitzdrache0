//! 焼きへ渡った空中遠近条件の最遠距離の報告。受け取るのは記録、返す代わりに機械可読な1行を標準出力へ出す。
//!
//! 最小と最大を並べるのは、実行の途中で1フレームだけ別の距離が混じった場合も検収が落とせるようにするためである。
//! 判定は`cargo xtask sky-lut`がこの行を読み、カメラの遠クリップと一致することを課す。
//!
//! 距離が無い実行(空を持たない世界)ではマジック値を置かず「なし」と書く。数として読めないことが
//! 検収の破れとして現れ、「0メートルで焼いた」という誤った読みにならない。

use blitz_math::メートル;

use crate::app::time_of_day::空中遠近の最遠距離の記録;

pub(crate) fn 空中遠近の最遠距離を表示する(記録: &空中遠近の最遠距離の記録) {
    println!(
        "空中遠近の最遠距離 組んだフレーム数={} 最小={} 最大={}",
        記録.組んだフレーム数(),
        距離の表記(記録.最小()),
        距離の表記(記録.最大())
    );
}

fn 距離の表記(距離: Option<メートル>) -> String {
    match 距離 {
        Some(距離) => format!("{}", 距離.値()),
        None => "なし".to_string(),
    }
}
