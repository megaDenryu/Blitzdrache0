//! 反復回数と刻み幅を変えたときの硬さの記録(Issue #36「検証」の反復回数とdtの項)。CPUの参照計算で同じ経過時間(4秒)だけ進め、
//! 下端の行の平均の高さ・伸びの平均(拘束違反の符号付きの平均)・拘束違反の二乗平均平方根を並べる。GPUと突き合わせた刻み数(十数本)は
//! 落下の途中であるため、硬さは別に長い経過時間で採る。曲げを持たない布は面の外へ座屈して揺れるため、下端の高さは条件の並びで単調にならず、
//! 伸びの平均と拘束違反が硬さの読みどころである。
//! 反復回数と刻み幅の組は、1/60秒で反復1・2・4・8回、1/120秒で反復4回(刻み数を倍にして同じ経過時間)である。

use blitz_math::秒;
use blitz_sim::刻み幅;

use super::lines;
use crate::app::cloth_reference::布の参照比較;

/// (反復回数, 刻み幅の分母)の組。1/120秒は刻み数を倍にして同じ経過時間で比べる。
const 条件の候補: [(u32, u32); 5] = [(1, 60), (2, 60), (4, 60), (8, 60), (4, 120)];
/// 硬さを採る経過時間(秒)。落下の途中でなく定常へ近い長さとして選ぶ。
const 経過時間の秒: u32 = 4;

pub(super) fn 硬さを出す(比較: &布の参照比較) {
    let 題材 = 比較.題材();
    for (反復回数, 刻み幅の分母) in 条件の候補 {
        let 刻み幅 = match 刻み幅::生成する(秒::生成する(1.0 / f32::from(u16::try_from(刻み幅の分母).unwrap_or(u16::MAX)))) {
            Ok(刻み幅) => 刻み幅,
            Err(誤り) => return lines::中止を出す(&format!("硬さの記録の刻み幅を作れない: {誤り}")),
        };
        let 刻み数 = 経過時間の秒 * 刻み幅の分母;
        match 題材.回す(題材.刻み幅を変えた条件(刻み幅), 反復回数, 刻み数) {
            Ok(参照) => lines::硬さを出す(&lines::硬さの観測 {
                反復回数,
                刻み幅の分母,
                刻み数,
                下端の平均の高さ: 下端の行の平均の高さ(参照.位置一覧(), 題材.一辺粒子数),
                伸びの平均: 参照.拘束違反の平均(),
                拘束違反の二乗平均平方根: 参照.拘束違反の二乗平均平方根(),
            }),
            Err(誤り) => lines::中止を出す(&format!("硬さの記録の参照計算を作れない: {誤り}")),
        }
    }
}

/// 粒子の並びは行0が上端であり、下端の行は末尾の一辺粒子数ぶんである。曲げの硬さの記録も読む。
pub(super) fn 下端の行の平均の高さ(位置一覧: &[blitz_math::位置<blitz_math::ワールド>], 一辺粒子数: u32) -> f32 {
    let 一辺 = usize::try_from(一辺粒子数).unwrap_or_else(|_| panic!("一辺粒子数がusizeに収まらない"));
    let 下端 = &位置一覧[位置一覧.len() - 一辺..];
    let 合計: f32 = 下端.iter().map(|位置| 位置.y().値()).sum();
    合計 / f32::from(u16::try_from(一辺粒子数).unwrap_or(u16::MAX))
}
