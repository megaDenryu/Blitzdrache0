//! 読み戻しと参照計算の突き合わせ: 位置と乗数(距離拘束と目標拘束)の差の最大と平均、GPUの位置での拘束違反、非有限値の有無。
//! 判定はしない(許容差との比較はxtaskが持つ)。非有限値はそのまま最大差へ現れる(比較の前に落とさない)。

use blitz_math::{メートル, ワールド, 位置};
use blitz_render::cloth_material::布の読み戻し;
use blitz_sim::constraint_graph::拘束違反の二乗平均平方根;
use blitz_sim::布の参照計算;

pub(super) struct 突き合わせの結果 {
    pub(super) gpuの拘束違反の二乗平均平方根: f64,
    pub(super) 位置の最大差: f64,
    pub(super) 位置の平均差: f64,
    pub(super) 乗数の最大差: f64,
    pub(super) 乗数の平均差: f64,
    pub(super) 全て有限か: bool,
}

pub(super) fn 突き合わせる(読み戻し: &布の読み戻し, 参照: &布の参照計算) -> 突き合わせの結果 {
    let gpuの位置: Vec<位置<ワールド>> = 読み戻し.位置一覧.iter().map(|成分| 読み戻した成分から位置を組む(*成分)).collect();
    let (位置の最大差, 位置の平均差) = 差の最大と平均(
        gpuの位置
            .iter()
            .zip(参照.位置一覧())
            .map(|(gpu, cpu)| f64::from((*gpu - *cpu).長さ().値())),
    );
    let (乗数の最大差, 乗数の平均差) = 差の最大と平均(
        読み戻し
            .ラグランジュ乗数一覧
            .iter()
            .zip(参照.ラグランジュ乗数一覧())
            .chain(読み戻し.目標拘束のラグランジュ乗数一覧.iter().zip(参照.目標拘束のラグランジュ乗数一覧()))
            .map(|(gpu, cpu)| f64::from((gpu - cpu.値()).abs())),
    );
    突き合わせの結果 {
        gpuの拘束違反の二乗平均平方根: 拘束違反の二乗平均平方根(参照.拘束一覧(), &gpuの位置),
        位置の最大差,
        位置の平均差,
        乗数の最大差,
        乗数の平均差,
        全て有限か: 読み戻し.位置一覧.iter().all(|成分| 成分.iter().all(|値| 値.is_finite()))
            && 読み戻し.ラグランジュ乗数一覧.iter().all(|値| 値.is_finite())
            && 読み戻し.目標拘束のラグランジュ乗数一覧.iter().all(|値| 値.is_finite()),
    }
}

fn 読み戻した成分から位置を組む(成分: [f32; 3]) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(成分[0]), メートル::生成する(成分[1]), メートル::生成する(成分[2]))
}

/// 非有限値は最大値の比較で必ず勝つように扱う(比較で落ちて見えなくなることを避ける)。
fn 差の最大と平均(差一覧: impl Iterator<Item = f64>) -> (f64, f64) {
    let mut 最大 = 0.0f64;
    let mut 合計 = 0.0f64;
    let mut 件数 = 0u32;
    for 差 in 差一覧 {
        最大 = if 差.is_nan() || 差 > 最大 { 差 } else { 最大 };
        合計 += 差;
        件数 += 1;
    }
    (最大, if 件数 == 0 { 0.0 } else { 合計 / f64::from(件数) })
}
