//! 曲げのコンプライアンスを変えたときの硬さの記録(Issue #38「検証シーン」の面)。CPUの参照計算で同じ題材(起動の指定の敷き方と固定)を経過時間2秒だけ進め、
//! 下端の行の平均の高さ・二面角の違反(二乗平均平方根・平均・最大。曲率の分布の代理)・伸びの平均を並べる。垂直に吊るした平らな布は曲げが働かないため、
//! この記録は水平に敷いた題材(`--cloth-xpbd-reference-shape horizontal-*`)だけで採る。反復回数と刻み幅の組は、1/60秒で反復4・16回、1/120秒で反復4回である。

use blitz_math::秒;
use blitz_sim::{刻み幅, 曲げのコンプライアンス};

use super::lines;
use crate::app::cloth_reference::布の参照比較;

/// 曲げのコンプライアンス(毎ニュートンメートル)の候補。0は硬い曲げ、1000はほぼ曲げ無しである。
const 曲げの候補: [f32; 4] = [0.0, 10.0, 100.0, 1000.0];
/// (反復回数, 刻み幅の分母)の組。
const 条件の候補: [(u32, u32); 3] = [(4, 60), (16, 60), (4, 120)];
/// 硬さを採る経過時間(秒)。水平に敷いた布が垂れ落ちて揺れが収まる長さとして選ぶ。
const 経過時間の秒: u32 = 2;

pub(super) fn 曲げの硬さを出す(比較: &布の参照比較) {
    let 題材 = 比較.題材();
    for 曲げの値 in 曲げの候補 {
        let 曲げ = match 曲げのコンプライアンス::生成する(曲げの値) {
            Ok(曲げ) => 曲げ,
            Err(誤り) => return lines::中止を出す(&format!("曲げの硬さの記録の曲げのコンプライアンスを作れない: {誤り}")),
        };
        for (反復回数, 刻み幅の分母) in 条件の候補 {
            let 刻み幅 = match 刻み幅::生成する(秒::生成する(1.0 / f32::from(u16::try_from(刻み幅の分母).unwrap_or(u16::MAX)))) {
                Ok(刻み幅) => 刻み幅,
                Err(誤り) => return lines::中止を出す(&format!("曲げの硬さの記録の刻み幅を作れない: {誤り}")),
            };
            let 刻み数 = 経過時間の秒 * 刻み幅の分母;
            match 題材.刻み幅と曲げを変えて回す(刻み幅, 曲げ, 反復回数, 刻み数) {
                Ok(参照) => {
                    let 統計 = 参照.曲げの違反の統計();
                    lines::曲げの硬さを出す(&lines::曲げの硬さの観測 {
                        曲げのコンプライアンス: 曲げの値,
                        反復回数,
                        刻み幅の分母,
                        刻み数,
                        下端の平均の高さ: super::stiffness::下端の行の平均の高さ(参照.位置一覧(), 題材.一辺粒子数),
                        二面角の違反の二乗平均平方根: 統計.二乗平均平方根,
                        二面角の違反の平均: 統計.絶対値の平均,
                        二面角の違反の最大: 統計.絶対値の最大,
                        伸びの平均: 参照.拘束違反の平均(),
                    });
                }
                Err(誤り) => lines::中止を出す(&format!("曲げの硬さの記録の参照計算を作れない: {誤り}")),
            }
        }
    }
}
