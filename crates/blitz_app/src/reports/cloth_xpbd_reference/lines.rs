//! 参照比較の報告の行の綴り。鍵は`鍵=値`の形で並べ、xtaskの検収(`xtask/src/cloth_xpbd_reference/parse.rs`)が同じ綴りで読む。
//! 綴りの契約は`cargo xtask conform`の台帳(`xtask/src/conform/wording_contract/table/cloth_xpbd_reference.rs`)が守る。

use blitz_sim::布の参照計算;

use super::comparison::突き合わせの結果;
use crate::app::cloth_reference::布の参照比較;

pub(super) fn 題材を出す(比較: &布の参照比較) {
    let 題材 = 比較.題材();
    println!(
        "布XPBD参照比較 刻み数={} 刻み幅={:.9e} 反復回数={} コンプライアンス={:.6e} 粒子数={} 拘束の数={} 色の数={} 目標拘束の数={}",
        比較.進めた刻み数(),
        題材.条件.刻み幅.秒().値(),
        題材.反復回数,
        題材.コンプライアンス,
        題材.拘束.拘束グラフ().点の数(),
        題材.拘束.拘束の数(),
        題材.拘束.色の区間一覧().len(),
        題材.目標拘束.拘束の数()
    );
}

/// 突き合わせができなかった理由。この行が出た実行には差の行が無く、検収はその不在で落ちる。
pub(super) fn 中止を出す(理由: &str) {
    println!("布XPBD参照比較の中止 理由={理由}");
}

pub(super) fn 差を出す(突き合わせ: &突き合わせの結果) {
    println!(
        "布XPBD参照比較の差 位置の最大差={:.6e} 位置の平均差={:.6e} 乗数の最大差={:.6e} 乗数の平均差={:.6e} 目標拘束の乗数の最大差={:.6e} 目標拘束の乗数の平均差={:.6e} 全て有限={}",
        突き合わせ.位置の最大差,
        突き合わせ.位置の平均差,
        突き合わせ.乗数の最大差,
        突き合わせ.乗数の平均差,
        突き合わせ.目標拘束の乗数の最大差,
        突き合わせ.目標拘束の乗数の平均差,
        if 突き合わせ.全て有限か { "はい" } else { "いいえ" }
    );
}

pub(super) fn 拘束違反を出す(突き合わせ: &突き合わせの結果, 参照: &布の参照計算) {
    println!(
        "布XPBD参照比較の拘束違反 GPUの拘束違反の二乗平均平方根={:.6e} CPUの拘束違反の二乗平均平方根={:.6e}",
        突き合わせ.gpuの拘束違反の二乗平均平方根,
        参照.拘束違反の二乗平均平方根()
    );
}

/// CPUの参照計算で反復回数と刻み幅を変えたときの硬さ。伸びの平均は拘束違反の符号付きの平均(伸びていれば正)である。
pub(super) fn 硬さを出す(条件: &硬さの観測) {
    println!(
        "布XPBD参照の硬さ 反復回数={} 刻み幅の分母={} 刻み数={} 下端の平均の高さ={:.6e} 伸びの平均={:.6e} CPUの拘束違反の二乗平均平方根={:.6e}",
        条件.反復回数, 条件.刻み幅の分母, 条件.刻み数, 条件.下端の平均の高さ, 条件.伸びの平均, 条件.拘束違反の二乗平均平方根
    );
}

/// 硬さの1条件の観測。
pub(super) struct 硬さの観測 {
    pub(super) 反復回数: u32,
    pub(super) 刻み幅の分母: u32,
    pub(super) 刻み数: u32,
    pub(super) 下端の平均の高さ: f32,
    pub(super) 伸びの平均: f64,
    pub(super) 拘束違反の二乗平均平方根: f64,
}
