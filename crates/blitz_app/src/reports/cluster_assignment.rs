//! クラスタの選別が作った割り当ての統計の1行出力。担当するのは行の綴りだけであり、数えるのはレンダラーの側である。
//!
//! 1行へまとめるのは、検収の入口が語頭で行を見つけて名前付きの数を読むためである
//! (`xtask/src/report_parse/line_read.rs`の`名前付きの数を読む`が読む形)。
//! 行の綴りを変えるときは`xtask/src/cluster_lights/assignment_parse.rs`も同時に直す。

use blitz_render::clustered_lighting::クラスタ選別の割り当て統計;

/// 語頭。検収の入口はこの語で行を見つける。
const 語頭: &str = "クラスタ割り当て";

pub(crate) fn 報告する(統計: クラスタ選別の割り当て統計) {
    println!(
        "{語頭} セル総数={} 宣言光数={} 光を持つセル数={} 総件数={} 最大件数={} 平均件数={:.4} 絞りの比={:.6} 偽陽性件数={} 偽陽性率={:.6}",
        統計.セルの総数(),
        統計.宣言した光の件数(),
        統計.光を1件以上持つセル数(),
        統計.割り当ての総件数(),
        統計.セルあたりの最大件数(),
        統計.セルあたりの平均件数(),
        統計.絞りの比(),
        統計.偽陽性の件数(),
        統計.偽陽性の率()
    );
}

pub(crate) fn 読み戻せなかったことを告げる(理由: &str) {
    println!("{語頭} 読み戻せなかった 理由={理由}");
}
