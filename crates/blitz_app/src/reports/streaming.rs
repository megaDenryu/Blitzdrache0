//! `--report-streaming`指定時に、そのフレームで起きたチャンクの読込・解除と予算判定をコンソールへ出す。
//! 既存の計測フラグへ相乗りさせないのは、フレーム時間の時系列を変える計測とチャンクの順序観測を混ぜないためである。
//! 呼び出しタイミング: 事象のあるフレームごとに呼ぶ。終了時に1回だけ出す要約は`streaming_summary`が持つ。

use blitz_engine::{ストリーミング進行, チャンク座標, 予算判定};

pub(crate) fn 進行を表示する(フレーム番号: u32, 進行: &ストリーミング進行) {
    if !進行.事象があるか() {
        return;
    }
    let 使用量 = 進行.使用量();
    println!("ストリーミング進行(フレーム{フレーム番号}):");
    println!("  台帳登録数: {}", 進行.台帳登録数());
    println!("  使用量: RAM {} bytes / VRAM {} bytes", 使用量.ramバイト数, 使用量.vramバイト数);
    一覧を表示する("読込開始", 進行.読込開始一覧());
    一覧を表示する("準備完了", 進行.準備完了一覧());
    一覧を表示する("CPUデータ破棄", 進行.cpuデータ破棄一覧());
    一覧を表示する("GPU資源解除待ち", 進行.gpu資源解除待ち一覧());
    判定を表示する(進行.判定());
}

fn 一覧を表示する(名前: &str, 座標一覧: &[チャンク座標]) {
    if 座標一覧.is_empty() {
        return;
    }
    let 並び: Vec<String> = 座標一覧.iter().map(|座標| format!("(x={}, z={})", 座標.x(), 座標.z())).collect();
    println!("  {名前}: {}", 並び.join(" "));
}

fn 判定を表示する(判定: &予算判定) {
    match 判定 {
        予算判定::全件収容 => println!("  予算判定: 全件収容"),
        予算判定::縮退 {
            最初の除外,
            ram超過,
            vram超過,
        } => println!(
            "  予算判定: 縮退(最初の除外 (x={}, z={}) / RAM超過 {ram超過} / VRAM超過 {vram超過})",
            最初の除外.x(),
            最初の除外.z()
        ),
        予算判定::使用量超過による退避 {
            退避一覧, 退避後も超過
        } => {
            println!("  予算判定: 使用量超過による退避({}件 / 退避後も超過 {退避後も超過})", 退避一覧.len());
            一覧を表示する("退避", 退避一覧);
        }
        予算判定::優先度退避 {
            最初の除外, 退避一覧
        } => {
            println!(
                "  予算判定: 優先度退避(収容を待つ (x={}, z={}) / {}件)",
                最初の除外.x(),
                最初の除外.z(),
                退避一覧.len()
            );
            一覧を表示する("退避", 退避一覧);
        }
    }
}
