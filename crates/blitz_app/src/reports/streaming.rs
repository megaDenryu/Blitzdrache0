//! `--report-streaming`指定時に、そのフレームで起きたチャンクの読込・解除と予算判定をコンソールへ出す。
//! 既存の計測フラグへ相乗りさせないのは、フレーム時間の時系列を変える計測とチャンクの順序観測を混ぜないためである。

use blitz_engine::{ストリーミング進行, チャンク座標, 予算判定};

use crate::app::ストリーミング要約;

/// `--report-streaming-summary`指定時の終了時出力。運んだ量は起動からの累計、使用量は各フレームで台帳が導出した値の最大である。
pub(crate) fn 要約を表示する(要約: &ストリーミング要約) {
    println!("ストリーミング要約:");
    println!("  観測フレーム数: {}", 要約.観測フレーム数);
    println!("  縮退フレーム数: {}", 要約.縮退フレーム数);
    println!(
        "  ディスク読込: {}件 / {} bytes",
        要約.転送量.ディスク読込件数(),
        要約.転送量.ディスク読込バイト数()
    );
    println!(
        "  GPU転送: {}件 / {} bytes(見積)",
        要約.転送量.gpu転送件数(),
        要約.転送量.gpu転送バイト数()
    );
    println!("  GPU資源解除: {}件", 要約.転送量.gpu解除件数());
    println!("  上限: RAM {} bytes / VRAM {} bytes", 要約.上限.ramバイト数, 要約.上限.vramバイト数);
    println!(
        "  最大使用量: RAM {} bytes / VRAM {} bytes",
        要約.最大使用量.ramバイト数, 要約.最大使用量.vramバイト数
    );
    println!("  最大台帳登録数: {}", 要約.最大台帳登録数);
    処理時間を表示する(要約);
}

/// 調停と描画束の追加解除がメインスレッドを占めた時間。フレーム間隔の計測とは別の量であり、混同しないよう区間名を明示する。
fn 処理時間を表示する(要約: &ストリーミング要約) {
    let Some(統計) = &要約.処理時間統計 else {
        println!("  ストリーミング処理時間: 計測できなかった(ウォームアップ後のフレームがない)");
        return;
    };
    println!("  ストリーミング処理時間(調停+描画束の追加解除、先頭120フレーム除外):");
    println!("    標本数: {}", 統計.標本数);
    println!("    平均: {:.4} ms", 統計.平均ms);
    println!("    p50: {:.4} ms", 統計.p50ms);
    println!("    p95: {:.4} ms", 統計.p95ms);
    println!("    p99: {:.4} ms", 統計.p99ms);
    println!("    最大: {:.4} ms", 統計.最大ms);
}

pub(crate) fn 進行を表示する(フレーム番号: u32, 進行: &ストリーミング進行) {
    if !進行.事象があるか() {
        return;
    }
    let 使用量 = 進行.使用量();
    println!("ストリーミング進行(フレーム{フレーム番号}):");
    println!("  台帳登録数: {}", 進行.台帳登録数());
    println!("  使用量: RAM {} bytes / VRAM {} bytes", 使用量.ramバイト数, 使用量.vramバイト数);
    一覧を表示する("読込開始", 進行.読込開始一覧());
    一覧を表示する("準備完了", 進行.準備完了一覧());
    一覧を表示する("CPUデータ破棄", 進行.cpuデータ破棄一覧());
    一覧を表示する("GPU資源解除待ち", 進行.gpu資源解除待ち一覧());
    判定を表示する(進行.判定());
}

fn 一覧を表示する(名前: &str, 座標一覧: &[チャンク座標]) {
    if 座標一覧.is_empty() {
        return;
    }
    let 並び: Vec<String> = 座標一覧.iter().map(|座標| format!("(x={}, z={})", 座標.x(), 座標.z())).collect();
    println!("  {名前}: {}", 並び.join(" "));
}

fn 判定を表示する(判定: &予算判定) {
    match 判定 {
        予算判定::全件収容 => println!("  予算判定: 全件収容"),
        予算判定::縮退 {
            最初の除外,
            ram超過,
            vram超過,
        } => println!(
            "  予算判定: 縮退(最初の除外 (x={}, z={}) / RAM超過 {ram超過} / VRAM超過 {vram超過})",
            最初の除外.x(),
            最初の除外.z()
        ),
        予算判定::使用量超過による退避 {
            退避一覧, 退避後も超過
        } => {
            println!("  予算判定: 使用量超過による退避({}件 / 退避後も超過 {退避後も超過})", 退避一覧.len());
            一覧を表示する("退避", 退避一覧);
        }
    }
}
