//! 実表示時刻(VK_KHR_present_wait)の観測を、停止時間の分布つきで表示する。
//! 停止時間を伏せて間隔だけ出すと、観測時刻が実表示時刻かどうかを読み手が判定できなくなるため必ず併記する。

use blitz_render::{実表示観測, 実表示計測状況};

use crate::app::フレーム時間統計;

/// 観測時刻を実表示時刻とみなせる下限。これ未満の停止時間は、待機前に既に表示されていたことを意味する。
const 実表示とみなす停止時間MS: f64 = 1.0;

pub(crate) fn 実表示間隔を表示する(状況: Option<実表示計測状況>, 観測一覧: &[実表示観測]) {
    println!("実表示間隔(VK_KHR_present_id + VK_KHR_present_wait、先頭120観測除外):");
    println!("  注意: この計測は表示まで描画ループを止める(毎フレーム約16ms)。フレームペーシングを変えうる条件下の値である。");
    println!("  注意: 既存の性能時系列と比較する値は、この計測を有効にしない`cargo xtask bench`で採ること。");
    println!("  注意: 素の条件と比べるときは交互に実行すること。同一コードでも時間帯によって25ms超過が0回から156回まで動く実測がある。");
    match 状況 {
        Some(状況) => println!("  対応状況: {}", 状況.名称()),
        None => println!("  対応状況: レンダラーが生成されなかったため判定できなかった"),
    }
    if 観測一覧.is_empty() {
        println!("  観測数: 0(計測できなかった)");
        return;
    }
    内訳を表示する(観測一覧);
    分布を表示する("実表示間隔", 間隔の一覧を集める(観測一覧));
    分布を表示する("停止時間", 停止時間の一覧を集める(観測一覧));
}

fn 内訳を表示する(観測一覧: &[実表示観測]) {
    let 時間切れ = 観測一覧
        .iter()
        .filter(|観測| matches!(観測, 実表示観測::待機が時間切れになった { .. }))
        .count();
    let 停止が短い = 観測一覧.iter().filter(|観測| 観測.停止時間ms() < 実表示とみなす停止時間MS).count();
    println!("  観測数: {}", 観測一覧.len());
    println!("  待機が時間切れになった: {時間切れ}回");
    println!("  停止時間が{実表示とみなす停止時間MS:.1}ms未満(観測時刻が実表示時刻からずれる): {停止が短い}回");
}

fn 間隔の一覧を集める(観測一覧: &[実表示観測]) -> Vec<f64> {
    観測一覧.iter().filter_map(|観測| 観測.前回からの間隔ms()).collect()
}

fn 停止時間の一覧を集める(観測一覧: &[実表示観測]) -> Vec<f64> {
    観測一覧.iter().map(|観測| 観測.停止時間ms()).collect()
}

fn 分布を表示する(名前: &str, 一覧ms: Vec<f64>) {
    let Some(統計) = crate::app::集計する(&一覧ms) else {
        println!("  {名前}: 該当する観測が無かった");
        return;
    };
    統計を表示する(名前, &統計);
}

fn 統計を表示する(名前: &str, 統計: &フレーム時間統計) {
    println!(
        "  {名前}: 標本{} / 平均 {:.4} / p50 {:.4} / p95 {:.4} / p99 {:.4} / 最大 {:.4} ms / 25ms超過 {}回",
        統計.標本数, 統計.平均ms, 統計.p50ms, 統計.p95ms, 統計.p99ms, 統計.最大ms, 統計.二十五ms超過数
    );
}
