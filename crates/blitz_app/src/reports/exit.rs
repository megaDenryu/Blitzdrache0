//! 終了時にどの報告を出すかの取りまとめ。受け取るのはアプリ、返すものは無く、指定された報告だけをコンソールへ出す。
//! 注意: レンダラー内部を読む報告(GPU時間・GPUメモリ・描画発行)は破棄より前に呼ぶ必要があるため、この工程は
//! `レンダラーを破棄する`より前に1回だけ呼ぶ。

use super::{display_timing, streaming_summary};
use crate::app::アプリ;

pub(crate) fn 終了時報告を出す(アプリ: &アプリ) {
    if アプリ.gpu時間報告が必要か() {
        super::gpu時間表を表示する(&アプリ.パス別gpu時間を取得する());
    }
    if アプリ.gpuメモリ報告が必要か() {
        match アプリ.gpuメモリ統計を取得する() {
            Some(統計) => super::gpuメモリ統計を表示する(&統計),
            None => println!("Vulkanメモリ確保: レンダラーが生成されなかったため取得できない"),
        }
    }
    if アプリ.描画発行報告が必要か() {
        match アプリ.描画発行内訳を取得する() {
            Some(内訳) => super::draw_issue::描画発行内訳を表示する(&内訳),
            None => println!("描画発行内訳: レンダラーが生成されなかったため取得できない"),
        }
        super::draw_issue::段切替回数を表示する(アプリ.個体詳細段切替回数を取得する());
        super::draw_issue::可視材料登録数を表示する(アプリ.可視材料登録数を取得する());
        let (読込総数, 起動後読込) = アプリ.シーン読込回数を取得する();
        super::draw_issue::シーン読込回数を表示する(読込総数, 起動後読込);
    }
    if アプリ.フレーム時間報告が必要か() {
        match アプリ.フレーム時間統計を取得する() {
            Some(統計) => super::フレーム時間統計を表示する(&統計),
            None => println!("CPU側フレーム間隔: 計測できなかった(ウォームアップ後のフレームがない)"),
        }
        super::レンダラーcpu区間を表示する(アプリ.レンダラーcpu区間時間を取得する());
    }
    if アプリ.インスタンス区間報告が必要か() {
        if !アプリ.フレーム時間報告が必要か() {
            super::レンダラーcpu区間を表示する(アプリ.レンダラーcpu区間時間を取得する());
        }
        super::群選択区間を表示する(アプリ.群選択区間統計を取得する().as_ref());
    }
    if アプリ.ストリーミング要約報告が必要か() {
        match アプリ.ストリーミング要約を取得する() {
            Some(要約) => streaming_summary::表示する(&要約),
            None => println!("ストリーミング要約: --streamingが指定されていないため計測していない"),
        }
    }
    if アプリ.実表示時間報告が必要か() {
        display_timing::実表示間隔を表示する(アプリ.実表示計測状況を取得する(), アプリ.実表示観測一覧を取得する());
    }
}
