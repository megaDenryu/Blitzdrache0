//! 起動直後の1フレーム目に出す構成の要約。何がどう組まれているかを示すもので、実行後の計測値は含まない。
//! 呼ばれるのはレンダラーを作った直後とフレーム0の描画入力の組み立て時であり、終了時の計測表示とは呼び出し時点が違う。
//! デバイスの能力から決まる値はレンダラー生成の直後に、シーンから決まる値はフレーム0に出る。

pub(crate) fn 描画対象構成を表示する(描画対象数: usize) {
    println!("描画対象構成:");
    println!("  描画対象数: {描画対象数}");
    println!("  シーン描画発行数/フレーム: {描画対象数}");
    println!("  シャドウ描画発行数/フレーム: {描画対象数}");
}

/// 選定した物理デバイスの、索引化した材質テクスチャ表の容量に効く上限。合否は判定していないため、
/// 判定していないことも同じ行に書いて「行が出たから足りている」と読まれないようにする。
pub(crate) fn ディスクリプタ索引上限を表示する(上限: blitz_render::ディスクリプタ索引上限) {
    println!(
        "ディスクリプタ索引上限(合否は判定しない): シェーダー段あたりの画像ディスクリプタ{}個 / セットあたりの画像ディスクリプタ{}個 / シェーダー段あたりの資源合計{}個",
        上限.シェーダー段あたりの画像ディスクリプタ数(),
        上限.セットあたりの画像ディスクリプタ数(),
        上限.シェーダー段あたりの資源合計数()
    );
}

pub(crate) fn 描画視点構成を表示する(視点数: usize) {
    println!("描画視点構成:");
    println!("  視点数: {視点数}");
}

pub(crate) fn フレーム構成を表示する(構成: &blitz_render::フレーム構成) {
    println!("フレーム構成:");
    for 段階 in 構成.段階一覧() {
        println!("  {}", 段階.名称());
    }
}

pub(crate) fn 座標変換を表示する(
    大域位置: blitz_math::大域ワールド位置,
    カメラ相対結果: Result<blitz_math::カメラ相対位置, blitz_math::座標変換エラー>,
) {
    println!("座標変換:");
    println!(
        "  大域ワールド位置: [{:.4}, {:.4}, {:.4}] m",
        大域位置.x().値(),
        大域位置.y().値(),
        大域位置.z().値()
    );
    match カメラ相対結果 {
        Ok(位置) => println!("  カメラ相対位置: [{:.4}, {:.4}, {:.4}] m", 位置.x().値(), 位置.y().値(), 位置.z().値()),
        Err(誤り) => println!("  カメラ相対変換失敗: {誤り}"),
    }
}
