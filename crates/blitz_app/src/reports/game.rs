//! ゲームの進行の要約をコンソールへ表示する。`--game`を指定した実行だけが出す。
//!
//! 更新の回数を出すのは、絵がまだ変わらない工程でもゲーム更新が毎フレーム走ったことを実行の結果で確かめるためである。

use crate::game::ゲーム進行の要約;

pub(crate) fn ゲームの進行を表示する(要約: &ゲーム進行の要約) {
    println!("ゲームの進行:");
    println!("  ゲーム: {}", 要約.ゲームの表示名);
    println!("  ゲーム更新の回数: {}", 要約.ゲーム更新の回数);
    println!("  最後の進行段階: {}", 要約.最後の進行段階の呼び名);
    println!("  到達済みの目的地: {} / {}", 要約.到達済みの目的地数, 要約.目的地の総数);
}
