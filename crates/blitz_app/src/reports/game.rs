//! ゲームの進行の要約をコンソールへ表示する。`--game`を指定した実行だけが出す。
//!
//! 更新の回数を出すのは、絵がまだ変わらない工程でもゲーム更新が毎フレーム走ったことを実行の結果で確かめるためである。
//! プレイヤーの大域位置を出すのは、動く個体が実際に動いたことと、同じ引数の2回の実行が同じ位置で終わることを絵を見ずに確かめるためである。
//! 移動状態と問い合わせ件数と刻みの所要時間を出すのは、着地していることと、1刻みあたりの問い合わせ件数と時間の分布を
//! 性能予算の枠と突き合わせるためである。

use std::time::Duration;

use crate::game::{ゲーム進行の要約, 刻みの所要時間の要約, 問い合わせ件数の要約};
use blitz_math::大域ワールド位置;

pub(crate) fn ゲームの進行を表示する(要約: &ゲーム進行の要約, カメラ大域位置: 大域ワールド位置) {
    println!("ゲームの進行:");
    println!("  ゲーム: {}", 要約.ゲームの表示名);
    println!("  ゲーム更新の回数: {}", 要約.ゲーム更新の回数);
    println!("  最後の進行段階: {}", 要約.最後の進行段階の呼び名);
    println!("  到達済みの目的地: {} / {}", 要約.到達済みの目的地数, 要約.目的地の総数);
    let 位置 = 要約.プレイヤーの大域位置;
    println!(
        "  プレイヤーの大域位置: 東{:.6} 天頂{:.6} 南{:.6}",
        位置.x().値(),
        位置.y().値(),
        位置.z().値()
    );
    println!(
        "  カメラの大域位置: 東{:.6} 天頂{:.6} 南{:.6}",
        カメラ大域位置.x().値(),
        カメラ大域位置.y().値(),
        カメラ大域位置.z().値()
    );
    println!("  最後の移動状態: {}", 要約.最後の移動状態の呼び名);
    問い合わせ件数を表示する(要約.移動の問い合わせ件数);
    刻みの所要時間を表示する(要約.刻みの所要時間);
}

fn 問い合わせ件数を表示する(要約: 問い合わせ件数の要約) {
    match 要約 {
        問い合わせ件数の要約::まだ刻んでいない => println!("  移動の問い合わせ件数の合計: 0(刻みなし)"),
        問い合わせ件数の要約::刻んだ {
            回数,
            合計,
            最小,
            最大,
            平均,
        } => {
            println!("  移動の問い合わせ件数の合計: {合計}");
            println!("  1刻みの問い合わせ件数: 最小{最小}件 最大{最大}件 平均{平均:.3}件({回数}刻み)");
        }
    }
}

fn 刻みの所要時間を表示する(要約: 刻みの所要時間の要約) {
    match 要約 {
        刻みの所要時間の要約::まだ刻んでいない => println!("  ゲーム更新のCPU時間: 合計0.0マイクロ秒(0刻み)"),
        刻みの所要時間の要約::刻んだ {
            回数,
            合計,
            最小,
            中央値,
            九十九パーセント点,
            最大,
        } => {
            let 一刻みあたり = マイクロ秒(合計) / f64::from(回数);
            println!(
                "  ゲーム更新のCPU時間: 合計{:.1}マイクロ秒({回数}刻み、1刻みあたり{一刻みあたり:.2}マイクロ秒)",
                マイクロ秒(合計)
            );
            println!(
                "  1刻みのCPU時間の分布: 最小{:.2}マイクロ秒 p50 {:.2}マイクロ秒 p99 {:.2}マイクロ秒 最大{:.2}マイクロ秒",
                マイクロ秒(最小),
                マイクロ秒(中央値),
                マイクロ秒(九十九パーセント点),
                マイクロ秒(最大)
            );
        }
    }
}

fn マイクロ秒(時間: Duration) -> f64 {
    時間.as_secs_f64() * 1.0e6
}
