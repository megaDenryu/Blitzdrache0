//! ゲームの進行の要約をコンソールへ表示する。`--game`を指定した実行だけが出す。
//!
//! 更新の回数を出すのは、絵がまだ変わらない工程でもゲーム更新が毎フレーム走ったことを実行の結果で確かめるためである。
//! プレイヤーの大域位置を出すのは、動く個体が実際に動いたことと、同じ引数の2回の実行が同じ位置で終わることを絵を見ずに確かめるためである。
//! 移動状態と問い合わせ件数と刻みの所要時間を出すのは、着地していることと、1刻みあたりの問い合わせ件数と時間を
//! 性能予算の枠と突き合わせるためである。

use crate::game::ゲーム進行の要約;
use blitz_math::大域ワールド位置;

pub(crate) fn ゲームの進行を表示する(要約: &ゲーム進行の要約, カメラ大域位置: 大域ワールド位置) {
    println!("ゲームの進行:");
    println!("  ゲーム: {}", 要約.ゲームの表示名);
    println!("  ゲーム更新の回数: {}", 要約.ゲーム更新の回数);
    println!("  最後の進行段階: {}", 要約.最後の進行段階の呼び名);
    println!("  到達済みの目的地: {} / {}", 要約.到達済みの目的地数, 要約.目的地の総数);
    let 位置 = 要約.プレイヤーの大域位置;
    println!(
        "  プレイヤーの大域位置: 東{:.6} 天頂{:.6} 南{:.6}",
        位置.x().値(),
        位置.y().値(),
        位置.z().値()
    );
    println!(
        "  カメラの大域位置: 東{:.6} 天頂{:.6} 南{:.6}",
        カメラ大域位置.x().値(),
        カメラ大域位置.y().値(),
        カメラ大域位置.z().値()
    );
    println!("  最後の移動状態: {}", 要約.最後の移動状態の呼び名);
    println!("  移動の問い合わせ件数の合計: {}", 要約.移動の問い合わせ件数の合計);
    let 刻みの回数 = 要約.所要時間を測った刻みの回数;
    let 合計マイクロ秒 = 要約.刻みの所要時間の合計.as_secs_f64() * 1.0e6;
    let 一刻みあたりマイクロ秒 = if 刻みの回数 == 0 {
        0.0
    } else {
        合計マイクロ秒 / f64::from(刻みの回数)
    };
    println!("  ゲーム更新のCPU時間: 合計{合計マイクロ秒:.1}マイクロ秒({刻みの回数}刻み、1刻みあたり{一刻みあたりマイクロ秒:.2}マイクロ秒)");
}
