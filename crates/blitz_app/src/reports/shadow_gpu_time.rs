//! 距離区分別のシャドウパスのGPU時間を合計する工程。受け取るのはパス名と移動平均の表、返すのは合計ミリ秒である。
//!
//! シャドウは距離区分ごとに別のパスとして積むため、パス別の表は4行に分かれる。予算(シャドウ2.0msは4距離区分の合計で維持する)と
//! そのまま突き合わせられるよう、距離区分別の行に加えて合計を1行出す
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「予算」)。

use blitz_render::cascade::距離区分番号;

/// 距離区分別の行が1つも無ければ`None`。0.0を返すと「計測できなかった」と「0ミリ秒だった」を区別できない。
pub(crate) fn 距離区分別のシャドウの合計ミリ秒(表: &[(&'static str, f64)]) -> Option<f64> {
    let mut 合計 = 0.0;
    let mut 見つかった数 = 0;
    for 番号 in 距離区分番号::全距離区分() {
        let 名前 = 番号.シャドウパス名();
        if let Some(&(_, 平均ミリ秒)) = 表.iter().find(|&&(表の名前, _)| 表の名前 == 名前) {
            合計 += 平均ミリ秒;
            見つかった数 += 1;
        }
    }
    if 見つかった数 == 0 { None } else { Some(合計) }
}
