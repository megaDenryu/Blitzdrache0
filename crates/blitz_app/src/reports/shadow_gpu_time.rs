//! 距離区分別のシャドウパスのGPU時間を合計する工程。受け取るのはパス名と分布の表、返すのは合計の分布である。
//!
//! シャドウは距離区分ごとに別のパスとして積むため、パス別の表は4行に分かれる。予算(シャドウ2.6msは4距離区分の合計で維持する)と
//! そのまま突き合わせられるよう、距離区分別の行に加えて合計を1行出す
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「予算」)。

use blitz_render::cascade::距離区分番号;
use blitz_render::gpu_pass_timing::パス時間の分布;

/// 距離区分別の行が1つも無ければ`None`。0.0を返すと「計測できなかった」と「0ミリ秒だった」を区別できない。
/// 注意: 中央値と95パーセンタイルは距離区分ごとの分位の和であり、フレームごとの合計の分位ではない。
/// フレームごとの合計を保つ計器を持たないためであり、予算と突き合わせる目安として読む。
pub(crate) fn 距離区分別のシャドウの合計(表: &[(&'static str, パス時間の分布)]) -> Option<パス時間の分布> {
    let mut 合計: Option<パス時間の分布> = None;
    for 番号 in 距離区分番号::全距離区分() {
        let 名前 = 番号.シャドウパス名();
        if let Some(&(_, 分布)) = 表.iter().find(|&&(表の名前, _)| 表の名前 == 名前) {
            // 最初の1件を種にするのは、零を種にすると標本数の最小が常に0になり、標本の有無を読めなくなるためである。
            合計 = Some(合計.map_or(分布, |これまで| これまで.足し合わせる(分布)));
        }
    }
    合計
}
