//! 遠方環境の派生表現のGPU読み戻し報告。ウィンドウもスワップチェーンも作らず、ウィンドウなし実行のGPUで
//! 拡散照度・鏡面畳込み・反射率積分表を焼いて読み戻し、解析解との一致・全体の統計・CPU正本との差・
//! 面境界の連続性を機械可読な行として標準出力へ出す。判定は`cargo xtask derived-environment`がこの出力を読んで行う。
//!
//! 遠方環境を大気から焼かずホストから与えるのは、畳み込みの正しさを解析解と突き合わせるためである。
//! 定数の環境を2つ入れて拡散照度が円周率×放射輝度・鏡面畳込みがどの粗さ段も放射輝度そのものになることを見る。
//! 方向性の強い環境は、粗さを上げたときのばらつきの減りと面境界の連続性と最詳細段の複製を見る。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「検収(機械判定)」

mod bake;
mod brdf_rows;
mod constant_rows;
mod directional_rows;
mod report_error;
mod representative_rows;
mod slices;
mod statistics;

use blitz_render::distant_environment::derived::{
    定数の遠方環境, 方向性の強い遠方環境, 立方体画像の一辺, 遠方環境の内容
};
use report_error::派生表現報告エラー;
use std::process::ExitCode;

/// 定数環境として入れる2つの放射輝度。2つ入れるのは、結果が入力に比例することを見るためである。
/// 1つだけでは、どんな入力にも同じ値を返す実装が通ってしまう。
const 定数環境の放射輝度一覧: [[f64; 3]; 2] = [[0.25, 1.5, 3.75], [1.0, 6.0, 15.0]];

pub(crate) fn 派生表現表を出す() -> ExitCode {
    match 報告する() {
        Ok(()) => ExitCode::SUCCESS,
        Err(誤り) => {
            eprintln!("派生表現報告に失敗した: {誤り}");
            ExitCode::FAILURE
        }
    }
}

fn 報告する() -> Result<(), 派生表現報告エラー> {
    let 解像度 = bake::検査する解像度::既定値();
    let 一辺 = 解像度.鏡面畳込み.段の一辺(最詳細段(解像度));
    見出しを出す(解像度, 一辺);

    let mut 検証件数 = 0_u64;
    for 放射輝度 in 定数環境の放射輝度一覧 {
        let 環境 = 定数の遠方環境(一辺, 放射輝度)?;
        let 読み戻し = bake::焼く(&環境, 解像度)?;
        検証件数 += 読み戻し.検証件数();
        constant_rows::定数環境の判定を出す(&読み戻し, 解像度, 放射輝度);
    }

    let 環境 = 方向性の強い遠方環境(一辺)?;
    let 読み戻し = bake::焼く(&環境, 解像度)?;
    検証件数 += 読み戻し.検証件数();
    println!("検証層 状況={} 件数={検証件数}", 読み戻し.検証層の状況().呼び名());
    statistics::立方体の統計を出す("拡散", 読み戻し.拡散照度());
    statistics::立方体の統計を出す("鏡面", 読み戻し.鏡面畳込み());
    statistics::表の統計を出す(読み戻し.反射率積分表());
    directional_rows::方向性の判定を出す(&読み戻し, 解像度);
    representative_rows::代表テクセルを出す(&丸めた環境(&環境)?, &読み戻し, 解像度);
    brdf_rows::反射率積分表の代表を出す(&読み戻し, 解像度.反射率積分表)
}

/// CPU正本へ渡す環境は、GPUの画像が保つ半精度の値へ丸めておく。丸めをそろえないと、
/// 写しの誤りでない差が最初から乗る。
fn 丸めた環境(環境: &遠方環境の内容) -> Result<遠方環境の内容, 派生表現報告エラー> {
    Ok(環境.半精度へ丸める()?)
}

fn 最詳細段(解像度: bake::検査する解像度) -> blitz_render::distant_environment::derived::粗さ段 {
    let 全段 = 解像度.鏡面畳込み.全段();
    let Some(&段) = 全段.first() else {
        panic!("鏡面畳込みの解像度が段を1つも持たない");
    };
    段
}

fn 見出しを出す(解像度: bake::検査する解像度, 一辺: 立方体画像の一辺) {
    println!(
        "派生表現報告 拡散照度の一辺={} 鏡面最詳細段の一辺={} 鏡面粗さ段数={} 反射率積分表の横={} 反射率積分表の縦={}",
        解像度.拡散照度.面の一辺().値(),
        一辺.値(),
        解像度.鏡面畳込み.粗さ段数(),
        解像度.反射率積分表.横(),
        解像度.反射率積分表.縦()
    );
}
