//! `--report-draw-issue`の報告の節。受け取るのは終了時の観測一式、返すものは無い。担当するのは、最終フレームの描画発行内訳と、
//! それを読む人が並べて見る計数(可視個体の選別・セット別束縛・材質資源表・段切替・可視材料登録・シーン読込・点光源の影)を
//! この順で出すことである。

use blitz_render::レンダラー;

use crate::app::終了時の観測一式;
use crate::reports::{draw_issue, point_light_shadow};

pub(super) fn 描画発行の内訳の節を出す(観測: &終了時の観測一式<'_>) {
    match 観測.レンダラー {
        Some(レンダラー) => draw_issue::描画発行内訳を表示する(&レンダラー.描画発行内訳を取得する()),
        None => println!("描画発行内訳: レンダラーが生成されなかったため取得できない"),
    }
    draw_issue::可視個体の選別の計数を表示する(観測.描画束.選別の計器.計数);
    draw_issue::距離区分の世界メートル毎テクセルを表示する(観測.描画束.選別の計器.解像度密度);
    match 観測.レンダラー.map(レンダラー::セット別ディスクリプタ束縛回数を取得する) {
        Some(回数) => draw_issue::セット別束縛回数を表示する(回数),
        None => println!("  セット別ディスクリプタ束縛回数: レンダラーが生成されなかったため取得できない"),
    }
    match 観測.レンダラー.map(レンダラー::材質資源表の要約を取得する) {
        Some(要約) => draw_issue::材質資源表の要約を表示する(要約),
        None => println!("  材質資源表: レンダラーが生成されなかったため取得できない"),
    }
    draw_issue::段切替回数を表示する(観測.描画束.個体詳細段切替回数);
    draw_issue::可視材料登録数を表示する(観測.描画束.可視材料登録数);
    draw_issue::シーン読込回数を表示する(観測.検収の観測.シーン読込回数.総数, 観測.検収の観測.シーン読込回数.起動後);
    match 観測.レンダラー {
        Some(レンダラー) => point_light_shadow::点光源の影の記録内訳を表示する(&レンダラー.点光源の影の記録内訳を取得する()),
        None => println!("点光源の影の記録内訳: レンダラーが生成されなかったため取得できない"),
    }
}
