//! 描画発行の内訳と段の切替回数のコンソール出力。`--report-draw-issue`が指定されたときだけ呼ばれる。
//! 行の綴りは検収の`xtask/src/report_parse.rs`が読むため、既存の行を書き換えるとそちらも同時に直す必要がある。

/// 最終フレームの描画発行の内訳。直接インスタンス描画では発行回数が個体数に比例しないことと、
/// シーンと帯0から帯3が別々の視錐台で個体を絞ることと、同じ群の中で複数のLOD段が同時に立つことを、
/// パス別の5つの数字で示す。パスはシーンと帯の合計5つあり、それぞれ同じ5行の組で出る。
pub(crate) fn 描画発行内訳を表示する(内訳: &blitz_render::描画発行内訳) {
    println!("描画発行内訳(最終フレーム):");
    for パス in blitz_render::可視パス::全パス() {
        パス別発行を表示する(パス.名前(), 内訳.パス(パス));
    }
}

fn パス別発行を表示する(パス名: &str, 発行: &blitz_render::パス別描画発行) {
    println!("  {パス名}発行数: {}", 発行.発行数());
    println!("  {パス名}候補数: {}", 発行.候補数());
    println!("  {パス名}可視数: {}", 発行.可視数());
    println!("  {パス名}個体数: {}", 発行.個体数());
    println!("  {パス名}段別個体数: {}", 段別個体数を並べる(発行.段別個体数()));
}

/// 段番号と個体数の対を段番号の昇順で並べた1行。段を1つしか使わない世界でも同じ形で出る。
fn 段別個体数を並べる(段別: &blitz_render::段別個体数) -> String {
    let 並び: Vec<String> = 段別
        .段ごと()
        .iter()
        .enumerate()
        .map(|(段番号, 個体数)| format!("{段番号}={個体数}"))
        .collect();
    if 並び.is_empty() {
        return "なし".to_string();
    }
    並び.join(" ")
}

/// ディスクから実行時シーンを読んだ回数。段の選択がディスクI/Oを起こさないことを、起動後の数が0であることで見る。
pub(crate) fn シーン読込回数を表示する(総数: u64, 起動後: u64) {
    println!("  シーン読込回数: {総数}");
    println!("  起動後シーン読込回数: {起動後}");
}

/// 起動から現在までに個体の段が入れ替わった延べ回数。ヒステリシス帯の内側での往復で段が振動していないことを、この数で見る。
pub(crate) fn 段切替回数を表示する(回数: u64) {
    println!("  個体LOD段切替回数: {回数}");
}

/// 可視判定と段選択へ登録されている群の件数。束の追加で材料と段の記憶が生まれ、解除で漏れなく消えることを、
/// 束が出入りする実行とそうでない実行でこの数を突き合わせて見る。
pub(crate) fn 可視材料登録数を表示する(件数: usize) {
    println!("  可視材料登録数: {件数}");
}

/// 最終フレームに群選択が数えた計数。レンダラー側の描画発行内訳とは出どころが違い、同じ数が両側で一致することが
/// 判定した集合と実際に描いた集合の整合の証拠になる。
/// 帯和集合可視数だけは発行の側から作れない。帯別の可視数を足すと複数の帯へ属する個体を重複して数えるためであり、
/// 「影を落とすべき個体が1体も落ちていない」ことはこの数だけが言える。
pub(crate) fn 群選択計数を表示する(計数: blitz_engine::可視判定計数) {
    println!("  群選択候補数: {}", 計数.候補数());
    println!("  群選択個体判定数: {}", 計数.個体判定数());
    println!("  群選択シーン可視数: {}", 計数.シーン可視数());
    println!("  群選択帯別可視数: {}", 帯別可視数を並べる(計数.帯別可視数()));
    println!("  群選択帯和集合可視数: {}", 計数.帯和集合可視数());
}

/// 帯番号と可視数の対を帯番号の昇順で並べた1行。
fn 帯別可視数を並べる(帯別: [usize; blitz_render::cascade::帯数]) -> String {
    let 並び: Vec<String> = 帯別.iter().enumerate().map(|(番号, 可視数)| format!("{番号}={可視数}")).collect();
    並び.join(" ")
}
