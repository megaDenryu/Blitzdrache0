//! 描画発行の内訳と段の切替回数のコンソール出力。`--report-draw-issue`が指定されたときだけ呼ばれる。
//! 行の綴りは検収の`xtask/src/report_parse.rs`が読むため、既存の行を書き換えるとそちらも同時に直す必要がある。
//! GPU資源の束縛と材質資源表の計器の行は`binding_metrics`が持つ。

pub(crate) use binding_metrics::{セット別束縛回数を表示する, 材質資源表の要約を表示する};

mod binding_metrics;

/// 最終フレームの描画発行の内訳。直接インスタンス描画では発行回数が個体数に比例しないことと、
/// シーンと距離区分0から距離区分3が別々の視錐台で個体を絞ることと、同じ群の中で複数のLOD段が同時に立つことを、
/// パス別の数字で示す。パスはシーンと距離区分の合計5つあり、それぞれ同じ行の組で出る。
/// 記録側の3行は作業領域が積んだ発行数とは観測地点が違う。発行数がCPUの積んだ件数、描画数がGPUへ積んだ`vkCmdDrawIndexed`の回数である。
pub(crate) fn 描画発行内訳を表示する(内訳: &blitz_render::描画発行内訳) {
    println!("描画発行内訳(最終フレーム):");
    for パス in blitz_render::可視パス::全パス() {
        パス別発行を表示する(パス.名前(), 内訳.パス(パス));
    }
}

fn パス別発行を表示する(パス名: &str, 発行: &blitz_render::パス別描画発行) {
    println!("  {パス名}発行数: {}", 発行.発行数());
    println!("  {パス名}候補数: {}", 発行.候補数());
    println!("  {パス名}可視数: {}", 発行.可視数());
    println!("  {パス名}個体数: {}", 発行.個体数());
    println!("  {パス名}段別個体数: {}", 段別個体数を並べる(発行.段別個体数()));
    let 記録側 = 発行.記録側();
    println!("  {パス名}描画数: {}", 記録側.描画数());
    println!("  {パス名}パイプライン切替: {}", 記録側.パイプライン切替());
    println!("  {パス名}材質切替: {}", 記録側.材質切替());
}

/// 段番号と個体数の対を段番号の昇順で並べた1行。段を1つしか使わない世界でも同じ形で出る。
fn 段別個体数を並べる(段別: &blitz_render::段別個体数) -> String {
    let 並び: Vec<String> = 段別
        .段ごと()
        .iter()
        .enumerate()
        .map(|(段番号, 個体数)| format!("{段番号}={個体数}"))
        .collect();
    if 並び.is_empty() {
        return "なし".to_string();
    }
    並び.join(" ")
}

