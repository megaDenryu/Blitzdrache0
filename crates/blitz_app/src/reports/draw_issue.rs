/// 最終フレームに可視個体の選別が数えた計数。レンダラー側の描画発行内訳とは出どころが違い、同じ数が両側で一致することが
/// 判定した集合と実際に描いた集合の整合の証拠になる。
/// 距離区分の和集合の可視数だけは発行の側から作れない。距離区分別の可視数を足すと複数の距離区分へ属する個体を重複して数えるためであり、
/// 「影を落とすべき個体が1体も落ちていない」ことはこの数だけが言える。
pub(crate) fn 可視個体の選別の計数を表示する(計数: blitz_engine::可視判定計数) {
    println!("  選別候補数: {}", 計数.候補数());
    println!("  選別個体判定数: {}", 計数.個体判定数());
    println!("  選別シーン可視数: {}", 計数.シーン可視数());
    println!("  選別距離区分別の可視数: {}", 距離区分別の可視数を並べる(計数.距離区分別の可視数()));
    println!("  選別距離区分の和集合の可視数: {}", 計数.距離区分の和集合の可視数());
}

/// 最終フレームの判定が使った距離区分ごとの世界メートル毎テクセル。シャドウマップの1テクセルが世界で覆う長さであり、
/// 影の解像度密度そのものである。判定範囲を組み立てた正射影から直に導くため、報告の値と実際に描いた範囲がずれない。
pub(crate) fn 距離区分の世界メートル毎テクセルを表示する(密度: Option<blitz_render::cascade::影の解像度密度>) {
    match 密度 {
        Some(解像度密度) => {
            let 長さ一覧 = 解像度密度.距離区分ごとの世界メートル毎テクセル();
            let 並び: Vec<String> = 長さ一覧
                .iter()
                .enumerate()
                .map(|(番号, 長さ)| format!("{番号}={:.6}", 長さ.値()))
                .collect();
            println!("  距離区分の世界メートル毎テクセル: {}", 並び.join(" "));
        }
        None => println!("  距離区分の世界メートル毎テクセル: 1フレームも可視判定を行っていないため測っていない"),
    }
}

/// 距離区分番号と可視数の対を距離区分番号の昇順で並べた1行。
fn 距離区分別の可視数を並べる(距離区分別: [usize; blitz_render::cascade::距離区分数]) -> String {
    let 並び: Vec<String> = 距離区分別.iter().enumerate().map(|(番号, 可視数)| format!("{番号}={可視数}")).collect();
    並び.join(" ")
}
