//! 遠方環境キーの判定の報告。受け取るのは空描画方針と観測条件、返す代わりに条件ごとの指示を1行ずつ標準出力へ出す。
//!
//! ここが鍵の完全性の本番外の呼び出し元である。判定そのものは本番の描画が使う`遠方環境更新判定`をそのまま通し、
//! 条件を1つずつ動かしたときの指示を並べる。鍵が値の比較で決まることの反証可能性がこの並びにある。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「鍵の設計(2つの注意)」

use blitz_engine::sky::atmosphere::大気媒体方針;
use blitz_engine::sky::{スカイビューキー, 空描画方針, 遠方環境キー};
use blitz_render::atmosphere::スカイビュー観測条件;
use blitz_render::distant_environment::input::遠方環境の生成指示;

use crate::app::遠方環境更新判定;

pub(super) fn 鍵の判定を出す(空描画: 空描画方針, 観測条件: スカイビュー観測条件) {
    let 太陽天頂余弦 = 観測条件.太陽天頂余弦().値();
    let 基準 = 鍵を導く(空描画, 観測条件, 太陽天頂余弦, 空描画.太陽放射照度());
    let mut 判定 = 遠方環境更新判定::新規();
    行を出す("初回", 判定.判定する(基準));
    行を出す("同一条件", 判定.判定する(基準));
    // 太陽の方位は鍵の構成要素に1つも現れないため、方位だけを回したフレームの鍵は前回と同じ値になる。
    行を出す("太陽方位のみ変更", 判定.判定する(基準));
    行を出す(
        "太陽高度変更",
        判定.判定する(鍵を導く(空描画, 観測条件, 太陽天頂余弦 - 0.1, 空描画.太陽放射照度())),
    );
    行を出す(
        "太陽放射照度変更",
        判定.判定する(鍵を導く(空描画, 観測条件, 太陽天頂余弦 - 0.1, 空描画.太陽放射照度() + 1.0)),
    );
    行を出す("夜空放射輝度変更", 判定.判定する(夜空を変えた鍵(空描画, 観測条件, 太陽天頂余弦 - 0.1)));
}

fn 行を出す(条件: &str, 指示: 遠方環境の生成指示) {
    let 語 = match 指示 {
        遠方環境の生成指示::前の結果を使う => "前の結果を使う",
        遠方環境の生成指示::焼き直す => "焼き直す",
    };
    println!("遠方環境鍵 条件={条件} 指示={語}");
}

fn 鍵を導く(
    空描画: 空描画方針, 観測条件: スカイビュー観測条件, 太陽天頂余弦: f32, 太陽放射照度: f32
) -> 遠方環境キー {
    let スカイビュー = スカイビューキー::導く(大気媒体方針::地球標準().静的キー(), 太陽天頂余弦, 観測条件.観測高度());
    遠方環境キー::導く(スカイビュー, 太陽放射照度, 空描画.夜空放射輝度())
}

/// 夜空放射輝度だけを変えた鍵。放射輝度色の生成は値域の検証を伴うため、失敗したら元の値を使って
/// 「変えなかった」ことが指示の並びに現れるようにする(無言で別の値へ差し替えない)。
fn 夜空を変えた鍵(空描画: 空描画方針, 観測条件: スカイビュー観測条件, 太陽天頂余弦: f32) -> 遠方環境キー {
    let 元 = 空描画.夜空放射輝度().成分();
    let 変えた = blitz_engine::sky::放射輝度色::生成する(元[0], 元[1], 元[2] + 0.001).unwrap_or(空描画.夜空放射輝度());
    let スカイビュー = スカイビューキー::導く(大気媒体方針::地球標準().静的キー(), 太陽天頂余弦, 観測条件.観測高度());
    遠方環境キー::導く(スカイビュー, 空描画.太陽放射照度() + 1.0, 変えた)
}
