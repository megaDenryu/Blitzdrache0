//! 遠方環境の代表テクセルの選び方と、その1テクセルずつの報告。受け取るのは天空放射輝度供給と読み戻し、
//! 返す代わりに行を標準出力へ出す。
//!
//! 代表テクセルを選ぶのは、全テクセルのCPU正本を出すと9万8千テクセルぶんの表の参照が検収の時間に見合わないためである。
//! 面の中心・角・辺の中点という写像の性質が変わる位置を全6面で選び、全体の健全性は統計の行が受け持つ。

use blitz_render::atmosphere::{天空放射輝度供給, 遠方環境のテクセル値, 遠方環境の解像度};
use blitz_render::cube_image::立方体の全面;

use super::report_error::遠方環境報告エラー;

/// 面の中で選ぶ添字の位置。割合でなく端と中央の名前で持つのは、実数から添字への丸めを避けるためである。
#[derive(Clone, Copy)]
enum 面内の位置 {
    先頭,
    中央,
    末尾,
}

impl 面内の位置 {
    /// 一辺が2以上であることは解像度の生成が保証するため、末尾の引き算は下位あふれしない。
    fn 添字(self, 一辺: u32) -> u32 {
        match self {
            Self::先頭 => 0,
            Self::中央 => 一辺 / 2,
            Self::末尾 => 一辺 - 1,
        }
    }
}

/// 面内で見る4つの位置。中心・左上の角・右下の角・上辺の中点である。
const 面内の代表: [(面内の位置, 面内の位置); 4] = [
    (面内の位置::中央, 面内の位置::中央),
    (面内の位置::先頭, 面内の位置::先頭),
    (面内の位置::末尾, 面内の位置::末尾),
    (面内の位置::中央, 面内の位置::先頭),
];

pub(super) fn 代表テクセルを出す(
    供給: &天空放射輝度供給<'_>,
    解像度: 遠方環境の解像度,
    読み戻し: &[[f32; 4]],
) -> Result<(), 遠方環境報告エラー> {
    let 一辺 = 解像度.面の一辺();
    for 面 in 立方体の全面 {
        for (横の位置, 縦の位置) in 面内の代表 {
            let 横 = 横の位置.添字(一辺);
            let 縦 = 縦の位置.添字(一辺);
            let 期待 = 遠方環境のテクセル値(供給, 解像度, 面, 横, 縦)?.成分();
            let 実測 = テクセルを参照する(読み戻し, 解像度, 面.層番号(), 横, 縦);
            println!(
                "遠方環境代表 層={} 横={横} 縦={縦} 期待赤={:.9} 期待緑={:.9} 期待青={:.9} 実測赤={:.9} 実測緑={:.9} 実測青={:.9}",
                面.層番号(),
                期待[0],
                期待[1],
                期待[2],
                実測[0],
                実測[1],
                実測[2]
            );
        }
    }
    Ok(())
}

fn テクセルを参照する(読み戻し: &[[f32; 4]], 解像度: 遠方環境の解像度, 層: u32, 横: u32, 縦: u32) -> [f32; 3] {
    let 一辺 = usize::try_from(解像度.面の一辺()).unwrap_or(0);
    let 層 = usize::try_from(層).unwrap_or(0);
    let 横 = usize::try_from(横).unwrap_or(0);
    let 縦 = usize::try_from(縦).unwrap_or(0);
    let Some(テクセル) = 読み戻し.get(層 * 解像度.面のテクセル数() + 縦 * 一辺 + 横) else {
        panic!("読み戻しの範囲外を参照した(層{層} 横{横} 縦{縦})。代表テクセルの座標が解像度と食い違っている");
    };
    [テクセル[0], テクセル[1], テクセル[2]]
}
