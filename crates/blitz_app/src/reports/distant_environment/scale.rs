//! 空描画方針から天空放射輝度の尺度を作る工程と、太陽円盤放射輝度だけを変えた対照の尺度。
//! 受け取るのは空描画方針、返すのは尺度である。
//!
//! 対照をここへ置くのは、円盤の明るさが尺度へ入らないという契約が、方針から尺度への写しの場所で決まるためである。

use blitz_engine::sky::{放射輝度色, 空描画方針};
use blitz_render::atmosphere::天空放射輝度の尺度;

use super::report_error::遠方環境報告エラー;

/// 対照に使う太陽円盤放射輝度。既定の8.0に対して桁が変わる大きさを選ぶ。
/// 円盤が遠方環境へ入っていれば画素が動くのに、入っていなければ1ビットも動かない。
const 対照の太陽円盤放射輝度: f32 = 80.0;

pub(super) fn 尺度を作る(空描画: 空描画方針) -> Result<天空放射輝度の尺度, 遠方環境報告エラー> {
    Ok(天空放射輝度の尺度::生成する(
        空描画.太陽放射照度(),
        空描画.夜空放射輝度().成分(),
    )?)
}

/// 太陽円盤放射輝度だけを変えた空描画方針から尺度を作る。尺度の型が円盤を持たないこと自体が
/// 非二重計上の型による保証であり、この経路はその保証が方針から尺度への写しにも及ぶことを確かめる。
pub(super) fn 円盤だけ変えた尺度(空描画: 空描画方針) -> Result<天空放射輝度の尺度, 遠方環境報告エラー> {
    let 明るい円盤 = 放射輝度色::生成する(対照の太陽円盤放射輝度, 対照の太陽円盤放射輝度, 対照の太陽円盤放射輝度)?;
    let 変えた方針 = 空描画方針::生成する(
        空描画.夜空放射輝度(),
        明るい円盤,
        空描画.太陽円盤角半径(),
        空描画.観測高度(),
        空描画.太陽放射照度(),
    )?;
    尺度を作る(変えた方針)
}
