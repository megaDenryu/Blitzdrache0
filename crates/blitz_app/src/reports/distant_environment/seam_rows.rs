//! 遠方環境の面境界の連続性の報告。受け取るのは読み戻し、返す代わりに1行の最大差を標準出力へ出す。
//!
//! 突き合わせそのものは`reports::cube_seam`が担い、ここは遠方環境の解像度を渡して行を出すことだけを担う。
//! 派生表現の立方体画像も同じ突き合わせを使うため、稜線の導出を2箇所に持たない。

use blitz_render::atmosphere::遠方環境の解像度;

use crate::reports::cube_seam::面境界を突き合わせる;

pub(super) fn 面境界の連続性を出す(解像度: 遠方環境の解像度, 読み戻し: &[[f32; 4]]) {
    let 観測 = 面境界を突き合わせる(読み戻し, 解像度.面の一辺());
    println!("遠方環境面境界 稜線数={} 最大相対差={:.9}", 観測.稜線数, 観測.最大相対差);
}
