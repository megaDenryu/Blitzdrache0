//! 面境界の連続性の報告。受け取るのは読み戻し、返す代わりに1行の最大差を標準出力へ出す。
//!
//! 見るのは、隣り合う2つの面で同じ稜線に接するテクセル同士の値の差である。この2つは半テクセルぶん離れた
//! 別々の向きを標本しているため厳密には一致しないが、天空放射輝度が向きについて連続であるため差は小さいはずである。
//! 差が跳ねるのは面と向きの写像が食い違ったときであり、絵では面の継ぎ目の筋として現れる。

use blitz_render::atmosphere::{立方体の面, 遠方環境の解像度};

/// 突き合わせる稜線の組。左の面の横位置0の列と、右の面の横位置が最大の列が同じ稜線に接する。
/// 4つの側面が輪をなす並びを選ぶのは、この4つが横位置の端だけで隣接し、縦の添字がそのまま対応するためである。
const 稜線の組: [(立方体の面, 立方体の面); 4] = [
    (立方体の面::第一軸の正, 立方体の面::第三軸の正),
    (立方体の面::第三軸の正, 立方体の面::第一軸の負),
    (立方体の面::第一軸の負, 立方体の面::第三軸の負),
    (立方体の面::第三軸の負, 立方体の面::第一軸の正),
];

pub(super) fn 面境界の連続性を出す(解像度: 遠方環境の解像度, 読み戻し: &[[f32; 4]]) {
    let 一辺 = 解像度.面の一辺();
    let mut 最大相対差 = 0.0_f64;
    for (左の面, 右の面) in 稜線の組 {
        for 縦 in 0..一辺 {
            let 左 = テクセル(読み戻し, 解像度, 左の面.層番号(), 0, 縦);
            let 右 = テクセル(読み戻し, 解像度, 右の面.層番号(), 一辺 - 1, 縦);
            最大相対差 = 最大相対差.max(相対差(左, 右));
        }
    }
    println!("遠方環境面境界 稜線数={} 最大相対差={最大相対差:.9}", 稜線の組.len());
}

/// 成分ごとの相対差の最大。分母を2つの絶対値の大きい方に取るのは、0に近い成分で相対差が発散しないようにするためである。
/// どちらも0に近いときは差そのものが小さいため、下限を置いて絶対差の扱いへ落とす。
fn 相対差(左: [f32; 3], 右: [f32; 3]) -> f64 {
    let mut 最大 = 0.0_f64;
    for 添字 in 0..3 {
        let 左値 = f64::from(左[添字]);
        let 右値 = f64::from(右[添字]);
        let 分母 = 左値.abs().max(右値.abs()).max(1.0e-6);
        最大 = 最大.max((左値 - 右値).abs() / 分母);
    }
    最大
}

fn テクセル(読み戻し: &[[f32; 4]], 解像度: 遠方環境の解像度, 層: u32, 横: u32, 縦: u32) -> [f32; 3] {
    let 一辺 = usize::try_from(解像度.面の一辺()).unwrap_or(0);
    let 層 = usize::try_from(層).unwrap_or(0);
    let 横 = usize::try_from(横).unwrap_or(0);
    let 縦 = usize::try_from(縦).unwrap_or(0);
    let Some(テクセル) = 読み戻し.get(層 * 解像度.面のテクセル数() + 縦 * 一辺 + 横) else {
        panic!("読み戻しの範囲外を参照した(層{層} 横{横} 縦{縦})。面境界の座標が解像度と食い違っている");
    };
    [テクセル[0], テクセル[1], テクセル[2]]
}
