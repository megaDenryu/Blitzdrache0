//! 遠方環境の全テクセルの統計。受け取るのは読み戻した生の4成分の列、返す代わりに1行の統計を標準出力へ出す。
//!
//! 破れの件数を出すのは、代表テクセルの一致だけでは面の角や境界の壊れた値を見逃すためである。
//! 4成分目はシェーダーが予約として0を書くことをここが確かめる。

pub(super) fn 統計を出す(テクセル一覧: &[[f32; 4]]) {
    let mut 非有限 = 0_usize;
    let mut 負 = 0_usize;
    let mut 予約が非零 = 0_usize;
    let mut 最小 = f64::INFINITY;
    let mut 最大 = f64::NEG_INFINITY;
    for テクセル in テクセル一覧 {
        for 値 in &テクセル[0..3] {
            if !値.is_finite() {
                非有限 += 1;
                continue;
            }
            if *値 < 0.0 {
                負 += 1;
            }
            最小 = 最小.min(f64::from(*値));
            最大 = 最大.max(f64::from(*値));
        }
        if テクセル[3] != 0.0 {
            予約が非零 += 1;
        }
    }
    println!(
        "遠方環境統計 テクセル数={} 非有限={非有限} 負={負} 予約が非零={予約が非零} 最小={:.9} 最大={:.9}",
        テクセル一覧.len(),
        有限にする(最小),
        有限にする(最大)
    );
}

/// 全成分が非有限だった場合に無限大を出さないための下支え。統計の行そのものが読めなくなるのを避ける。
fn 有限にする(値: f64) -> f64 {
    if 値.is_finite() { 値 } else { 0.0 }
}
