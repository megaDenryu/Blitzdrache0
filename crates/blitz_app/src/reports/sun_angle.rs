//! その実行が使った太陽の角度のコンソール出力。`--report-sun-angle`が指定されたときだけ呼ばれる。
//! 行の綴りは`xtask/src/shadow_probe/parse.rs`が読むため、書き換えるならそちらも同時に直す。
//!
//! 高度と方位は天空状態の導出(球面天文学)がそのまま返す値であり、ここは度へ直して並べるだけである。
//! 計測が条件名でなくこの2つの角度を証拠に残すためにある。空の方針を持たない世界では導いていないことを行に書く。

use blitz_engine::sky::天空状態;

pub(crate) fn 太陽の角度を表示する(状態: Option<&天空状態>) {
    match 状態 {
        Some(状態) => {
            println!("  太陽高度度: {}", 状態.太陽高度().値().to_degrees());
            println!("  太陽方位度: {}", 状態.太陽方向().方位().値().to_degrees());
        }
        None => println!("太陽の角度: この世界は空の方針を持たないため導いていない"),
    }
}
