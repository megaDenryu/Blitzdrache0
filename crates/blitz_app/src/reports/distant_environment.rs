//! 遠方環境のGPU読み戻し報告。ウィンドウもスワップチェーンも作らず、ウィンドウなし実行のGPUで大気のベイク済み画像と
//! 遠方環境の立方体画像を焼いて読み戻し、鍵の判定・全体の統計・CPU正本との差・面境界の連続性を機械可読な行として
//! 標準出力へ出す。これが遠方環境生成シェーダーの本番外の呼び出し元であり、判定は
//! `cargo xtask distant-environment`がこの出力を読んで行う。
//!
//! 太陽円盤放射輝度だけを変えた空描画方針で2回焼くのは、円盤を二重に計上していないことの負の対照である。
//! 円盤の明るさは天空放射輝度の尺度に1つも現れないため、変えても画素は1ビットも動かないはずである。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「検収(機械判定)」

mod bake;
mod key_rows;
mod report_error;
mod representative_rows;
mod scale;
mod seam_rows;
mod statistics;

use blitz_engine::sky::atmosphere::大気媒体方針;
use blitz_engine::sky::空描画方針;
use blitz_render::atmosphere::{
    スカイビュー表, スカイビュー観測条件, 多重散乱表, 大気のベイク済み画像の解像度, 天空放射輝度の尺度, 天空放射輝度供給, 天頂余弦, 透過率表,
    遠方環境の解像度,
};
use report_error::遠方環境報告エラー;
use std::process::ExitCode;

/// 検査に使う太陽の天頂余弦。60度の高度に相当し、全面に散乱の寄与がある条件である。
/// 端の条件(天頂・地平線・地平線下)は6面それぞれの代表テクセルの取り方が覆う。
const 検査する太陽天頂余弦: f32 = 0.866_025_4;

pub(crate) fn 遠方環境表を出す() -> ExitCode {
    match 報告する() {
        Ok(()) => ExitCode::SUCCESS,
        Err(誤り) => {
            eprintln!("遠方環境報告に失敗した: {誤り}");
            ExitCode::FAILURE
        }
    }
}

fn 報告する() -> Result<(), 遠方環境報告エラー> {
    let 媒体 = crate::atmosphere_medium::大気散乱媒体へ写す(&大気媒体方針::地球標準())?;
    let 大気の解像度 = 大気のベイク済み画像の解像度::既定値();
    let 立方体の解像度 = 遠方環境の解像度::既定値();
    let 空描画 = 空描画方針::既定値();
    let 観測条件 = スカイビュー観測条件::生成する(空描画.観測高度(), 天頂余弦::生成する(検査する太陽天頂余弦)?)?;
    let 尺度 = scale::尺度を作る(空描画)?;
    見出しを出す(立方体の解像度, 観測条件, 尺度);
    key_rows::鍵の判定を出す(空描画, 観測条件);

    let 一回目 = bake::焼く(&媒体, 大気の解像度, 観測条件, 立方体の解像度, 尺度)?;
    let 円盤対照 = bake::焼く(&媒体, 大気の解像度, 観測条件, 立方体の解像度, scale::円盤だけ変えた尺度(空描画)?)?;
    println!(
        "検証層 状況={} 件数={}",
        一回目.検証層の状況().呼び名(),
        一回目.検証件数() + 円盤対照.検証件数()
    );
    println!(
        "遠方環境円盤対照 不一致={}",
        bake::不一致数(一回目.テクセル一覧(), 円盤対照.テクセル一覧())
    );
    statistics::統計を出す(一回目.テクセル一覧());

    let 透過率表 = 透過率表::焼く(媒体.消散(), 大気の解像度)?;
    let 多重散乱表 = 多重散乱表::焼く(&媒体, &透過率表, 大気の解像度)?;
    let スカイビュー表 = スカイビュー表::焼く(&媒体, &透過率表, &多重散乱表, 大気の解像度, 観測条件)?;
    let 供給 = 天空放射輝度供給::生成する(&媒体, &スカイビュー表, 観測条件, 尺度);
    representative_rows::代表テクセルを出す(&供給, 立方体の解像度, 一回目.テクセル一覧())?;
    seam_rows::面境界の連続性を出す(立方体の解像度, 一回目.テクセル一覧());
    Ok(())
}

fn 見出しを出す(解像度: 遠方環境の解像度, 観測条件: スカイビュー観測条件, 尺度: 天空放射輝度の尺度) {
    println!(
        "遠方環境報告 面の一辺={} 全テクセル数={} 観測高度={} 太陽天頂余弦={} 太陽放射照度={}",
        解像度.面の一辺(),
        解像度.全テクセル数(),
        観測条件.観測高度().値(),
        観測条件.太陽天頂余弦().値(),
        尺度.太陽放射照度()
    );
}
