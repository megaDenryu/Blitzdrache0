//! GPU上の自動露出とCPU正本を1行へ並べる報告。担当するのは「同じフレームの圧縮前のHDRから正本の
//! ヒストグラムと目標補正段を求め直し、GPUから読み戻した観測と並べて出す」ことである。合否は判定しない。
//!
//! 突き合わせをここが行うのは、CPU正本(`blitz_engine::auto_exposure`)を読めるのがコンポジションルートだけだからである。
//! 検収の入口は外部依存を持たない方針であり、正本の写しをもう1つ持つとその写しの正しさが検収の前提になる。
//!
//! 同じフレームの画素を見ていることが一致の前提である。読み戻すHDR中間画像は集計が読んだものと同じであり、
//! 明るさの圧縮はその画像を書き換えない。

use blitz_engine::auto_exposure::{
    添字の重み付き総和, 画素の割合, 画素を区分する, 画素列から集計する, 目標中間灰, 目標補正段を導く, 自動補正段の上下限, 輝度の区分,
    輝度ヒストグラム,
};
use blitz_render::HDR読み戻し画像;
use blitz_render::auto_exposure::{ビン数, 自動露出の観測};

/// 1画素あたりの成分数。読み戻したHDRはRGBAの4成分連結である。
const 画素あたり成分数: usize = 4;

pub(crate) fn 報告する(画像: &HDR読み戻し画像, 観測: &自動露出の観測, 探り色: Option<[f32; 3]>) {
    let 正本 = 画素列から集計する(画像.成分列().chunks_exact(画素あたり成分数).map(|画素| [画素[0], 画素[1], 画素[2]]));
    let 照合 = [
        ヒストグラムの照合(&正本, 観測),
        補正段の照合(&正本, 観測),
        探り色の照合(&正本, 観測, 探り色),
    ];
    println!("自動露出行 {}", 照合.join(" "));
}

/// 探り色がどのビンへ入ったかと、その位置のCPU正本とGPUの件数。指定が無い実行は「なし」を出す。
/// 探り色は積和融合の有無でビンが変わる組であるため、この位置の件数が食い違えば融合が起きたことになる。
fn 探り色の照合(正本: &輝度ヒストグラム, 観測: &自動露出の観測, 探り色: Option<[f32; 3]>) -> String {
    let Some([赤, 緑, 青]) = 探り色 else {
        return "探り色のビン=なし 探り色のCPU件数=なし 探り色のGPU件数=なし".to_string();
    };
    let 輝度の区分::ビンへ入る(添字) = 画素を区分する(赤, 緑, 青) else {
        return "探り色のビン=ビン外 探り色のCPU件数=0 探り色のGPU件数=0".to_string();
    };
    format!(
        "探り色のビン={} 探り色のCPU件数={} 探り色のGPU件数={}",
        添字.値(),
        正本.ビンの件数(添字).値(),
        観測.ビンの件数[添字.配列の位置()]
    )
}

/// 全ビンと2つの枠の一致を、最初に食い違った添字とともに出す。
fn ヒストグラムの照合(正本: &輝度ヒストグラム, 観測: &自動露出の観測) -> String {
    let 食い違い = (0..ビン数).find(|&位置| 正本.ビンの件数(添字(位置)).値() != 観測.ビンの件数[位置]);
    let 枠の一致 = 正本.零以下の件数().値() == 観測.零以下の件数 && 正本.非有限の件数().値() == 観測.非有限の件数;
    format!(
        "ビン一致={} 枠一致={} 最初の食い違いビン={} ビンへ入った総数={} 零以下={} 非有限={}",
        真偽(食い違い.is_none()),
        真偽(枠の一致),
        食い違い.map_or_else(|| "なし".to_string(), |位置| 位置.to_string()),
        正本.ビンへ入った総数().値(),
        観測.零以下の件数,
        観測.非有限の件数,
    )
}

/// CPU正本とGPUの導出を並べる。整数の中間値(添字の重み付き総和)を先に置くのは、そこが厳密一致を見る対象であり、
/// 目標補正段は整数から作る最後の数演算ぶんだけ食い違いうるからである。
fn 補正段の照合(正本: &輝度ヒストグラム, 観測: &自動露出の観測) -> String {
    let 導出 = 目標補正段を導く(正本, 目標中間灰::既定値(), 自動補正段の上下限::既定値());
    let 不能 = || "導出不能".to_string();
    let (cpu目標, cpu統計量, 上端到達率, 下端到達率) = 導出.as_ref().map_or_else(
        |_| (不能(), 不能(), 不能(), 不能()),
        |結果| {
            let 総和 = 結果.添字の重み付き総和().値().to_string();
            let 到達率 = |割合: 画素の割合| 割合.値().to_string();
            (
                結果.目標補正段().値().to_string(),
                総和,
                到達率(結果.上端のビンの到達率()),
                到達率(結果.下端のビンの到達率()),
            )
        },
    );
    let gpu統計量 = 添字の重み付き総和::二語から生成する(観測.添字の重み付き総和の上位の語, 観測.添字の重み付き総和の下位の語);
    format!(
        "CPU添字の重み付き総和={cpu統計量} GPU添字の重み付き総和={} CPU目標補正段={cpu目標} GPU目標補正段={} GPU補正段={} 初期化済み={} 導出不能フレーム数={} 上端到達率={上端到達率} 下端到達率={下端到達率}",
        gpu統計量.値(),
        観測.直近の目標補正段,
        観測.補正段,
        真偽(観測.初期化済み),
        観測.導出不能フレーム数
    )
}

fn 添字(位置: usize) -> blitz_engine::auto_exposure::ビンの添字 {
    let 値 = u8::try_from(位置).unwrap_or_else(|_| panic!("ビンの添字が8ビットに収まらない: {位置}"));
    blitz_engine::auto_exposure::ビンの添字::生成する(値).unwrap_or_else(|誤り| panic!("ビンの本数の中の位置から添字を作れなかった: {誤り}"))
}

fn 真偽(値: bool) -> &'static str {
    if 値 { "真" } else { "偽" }
}
