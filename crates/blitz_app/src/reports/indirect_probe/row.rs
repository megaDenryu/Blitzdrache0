//! 板1枚ぶんの照合結果を1行で出す工程。受け取るのは板番号と画素と期待と実測、返すのは無しである。
//! 判定は`cargo xtask indirect-probe`がこの行を読んで行う。
//!
//! 期待をsRGB相当の整数で出すのは、読み戻し画像がその形で返るためである。ポスト処理を外した実行では
//! 書き込みが「線形の放射輝度を0から1へ切り詰めてsRGB符号化した値」そのものになる。
//! 面と段の位置も並べるのは、値が合わなかったときに「どの面のどの段を参照したつもりか」を判定側が読めるようにするためである。

use blitz_render::atmosphere::立方体の面;

use super::expected_color::板の期待;
use super::projection::板の投影;
use crate::reports::sky_pixel::線形をsrgb8bit相当へ変換する;

pub(super) fn 行を出す(板番号: usize, 投影: &板の投影, 期待: &板の期待, 実測: [u8; 3]) {
    let 期待srgb = 期待.放射輝度.map(線形をsrgb8bit相当へ変換する);
    println!(
        "間接照明代表板 番号={} 画素={},{} 期待={:.3},{:.3},{:.3} 実測={},{},{} 面={} 段={:.4} 面余裕={:.4}",
        板番号,
        投影.横,
        投影.縦,
        期待srgb[0],
        期待srgb[1],
        期待srgb[2],
        実測[0],
        実測[1],
        実測[2],
        面の番号(期待.参照先.面),
        期待.参照先.段の位置,
        期待.参照先.面の端からの余裕()
    );
}

fn 面の番号(面: 立方体の面) -> u32 {
    面.層番号()
}
