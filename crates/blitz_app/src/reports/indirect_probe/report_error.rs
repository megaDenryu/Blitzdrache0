//! 間接照明の代表板の照合が途中で止まる原因。この報告は板ごとに行を出すだけであり、止まった板は理由を1行として
//! 出して次の板へ進むため、起動エラーへは合流させずこの報告の中で閉じる。

use blitz_math::座標変換エラー;
use thiserror::Error;

#[derive(Debug, Error)]
pub(super) enum 代表板の照合エラー {
    #[error("板の中心をカメラ相対へ写せなかった: {0}")]
    カメラ相対へ写せない(#[from] 座標変換エラー),

    #[error("板の中心がカメラの後ろにある")]
    板がカメラの後ろにある,

    #[error("板の中心がカメラの位置と重なっている")]
    板がカメラと重なっている,

    #[error("板の中心が画面の外にある(正規化デバイス座標{正規化デバイス座標})")]
    板が画面の外にある { 正規化デバイス座標: f64 },

    #[error("画素({横}, {縦})が読み戻し画像の外にある")]
    画素が画像の外にある { 横: u32, 縦: u32 },
}
