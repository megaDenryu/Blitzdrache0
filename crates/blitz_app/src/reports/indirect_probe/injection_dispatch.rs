//! 検収条件の中身をレンダラーのどちらの入口へ渡すかを決める工程。受け取るのは条件とレンダラー、返すのは注入の成否である。
//! 呼ばれるのはレンダラー生成の直後の1回だけである。
//!
//! 値の表と分けるのは、触れるものが違うためである。あちらは定数だけを持ち、こちらはレンダラーの可変の参照を取る。
//!
//! 縦結合の条件だけが別の入口へ行くのは、その条件が生成側を働かせるためである。残りの条件は生成側を止めて
//! 派生表現の中身を直に置き換える。

use blitz_render::distant_environment::{遠方環境の焼かせる解析入力, 遠方環境の解析入力};
use blitz_render::{レンダラー, レンダラーエラー};

use super::condition::{縦結合の放射輝度, 遠方環境の検収条件, 鏡面の表の2成分};

/// この条件がGPUへ与える中身。どちらの入口へ渡すかで、そのフレームに生成側が働くかどうかが変わる。
enum 注入の内容 {
    派生表現へ直に与える(遠方環境の解析入力),
    遠方環境へ与えて焼かせる(遠方環境の焼かせる解析入力),
}

pub(crate) fn レンダラーへ注入する(
    条件: 遠方環境の検収条件, レンダラー: &mut レンダラー
) -> Result<(), レンダラーエラー> {
    match 注入の内容を組む(条件) {
        注入の内容::派生表現へ直に与える(入力) => レンダラー.遠方環境の解析入力を注入する(&入力),
        注入の内容::遠方環境へ与えて焼かせる(入力) => レンダラー.遠方環境の焼かせる解析入力を注入する(&入力),
    }
}

fn 注入の内容を組む(条件: 遠方環境の検収条件) -> 注入の内容 {
    let 遠方環境の検収条件::縦結合の定数遠方環境 = 条件 else {
        return 注入の内容::派生表現へ直に与える(条件.焼き上がりの解析入力());
    };
    let 入力 = 遠方環境の焼かせる解析入力::生成する(縦結合の放射輝度, 鏡面の表の2成分)
        .unwrap_or_else(|誤り| panic!("縦結合の定数から焼かせる解析入力を作れなかった: {誤り}"));
    注入の内容::遠方環境へ与えて焼かせる(入力)
}
