//! 遠方環境の消費を判定する条件と、その条件が3つの画像へ与える値。担うのは条件の同一性と値の表だけであり、
//! GPUへの注入も期待値の計算も知らない。
//!
//! 注入する値と期待値を同じ表から出すのは、2箇所に置くと「注入した値と違う値で期待を組む」食い違いが
//! 画素の不一致としてしか現れないためである。値はこの1つの表が答え、注入も期待もここを読む。
//!
//! 値を0と1の間の中ほどへ取るのは、ポスト処理を外した実行の書き込みが「線形の放射輝度を0から1へ切り詰めて
//! sRGB符号化した値」になるためである。切り詰めに掛かる値を選ぶと、期待値と実測が上限で一致してしまい
//! 式の誤りを見逃す(参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」)。

use blitz_render::distant_environment::{遠方環境の解析入力, 鏡面畳込みの解析入力};

/// 縮小段と面を見分けるための色。段の判定でも面の判定でも同じ6色を使う。互いに3成分すべてで離れている。
const 見分けの色: [[f32; 3]; 6] = [
    [0.90, 0.10, 0.10],
    [0.10, 0.90, 0.10],
    [0.10, 0.10, 0.90],
    [0.90, 0.90, 0.10],
    [0.90, 0.10, 0.90],
    [0.10, 0.90, 0.90],
];

/// 拡散だけを立てる条件の照度。
const 拡散の照度: [f32; 3] = [0.6, 0.45, 0.3];

/// 鏡面を立てる条件の反射率積分表の2成分。垂直入射の反射率に掛かる倍率と、反射率に依らず足す量である。
const 鏡面の表の2成分: [f32; 2] = [0.8, 0.05];

/// 3つの機械判定の条件。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 遠方環境の検収条件 {
    /// 拡散照度だけを定数で立て、鏡面と反射率積分表を0にする。誘電体が`取り分×照度×ベースカラー/円周率`になり、
    /// 金属は取り分が0になって黒に落ちる。
    拡散だけの定数,
    /// 鏡面畳込みの縮小段ごとに違う色を置き、拡散を0にする。粗さが正しい段を選んでいるかを見る。
    鏡面の段別定数色,
    /// 鏡面畳込みの面ごとに違う色を置き、拡散を0にする。参照する向きが正しい面を選んでいるかを見る。
    鏡面の面別定数色,
}

impl 遠方環境の検収条件 {
    /// 起動引数の語から条件を選ぶ。知らない語は`None`にして、呼び出し元が起動引数の失敗として扱う。
    pub(crate) fn 語から選ぶ(語: &str) -> Option<Self> {
        match 語 {
            "diffuse" => Some(Self::拡散だけの定数),
            "specular-level" => Some(Self::鏡面の段別定数色),
            "specular-face" => Some(Self::鏡面の面別定数色),
            _ => None,
        }
    }

    /// この条件が3つの画像へ与える値。鏡面の段数は焼いた画像の段数と噛み合う必要があり、噛み合わなければ
    /// 注入の入口が型付きの失敗を返す。
    pub(crate) fn 解析入力を組む(self) -> 遠方環境の解析入力 {
        let (拡散, 鏡面, 表) = match self {
            Self::拡散だけの定数 => (
                拡散の照度,
                鏡面畳込みの解析入力::段ごとの一様な色(vec![[0.0; 3]; 見分けの色.len()]),
                [0.0, 0.0],
            ),
            Self::鏡面の段別定数色 => ([0.0; 3], 鏡面畳込みの解析入力::段ごとの一様な色(見分けの色.to_vec()), 鏡面の表の2成分),
            Self::鏡面の面別定数色 => ([0.0; 3], 鏡面畳込みの解析入力::面ごとの一様な色(見分けの色), 鏡面の表の2成分),
        };
        遠方環境の解析入力::生成する(拡散, 鏡面, 表).unwrap_or_else(|誤り| panic!("検収条件の定数から解析入力を作れなかった: {誤り}"))
    }
}
