//! 板の中心を読み戻し画像の画素へ写す工程。受け取るのは板の中心のワールド位置とそのフレームの視点、
//! 返すのは画素の位置と、その板から見た視線である。
//!
//! 画素の位置を検収の側で表に持たず毎回投影で求めるのは、構図が変わるたびに表が腐るためである。
//! 投影に使う行列は描画が使ったものそのものであり、板の見える位置と判定する位置が同じ1つの導出から出る。

use blitz_math::{大域メートル, 大域ワールド位置};

use crate::app::frame::フレーム視点;

/// 板の中心が写った画素と、そこから見た視線(表面からカメラへ向かう単位ベクトル)。
pub(super) struct 板の投影 {
    pub(super) 横: u32,
    pub(super) 縦: u32,
    pub(super) 視線: [f64; 3],
}

pub(super) fn 板の中心を投影する(
    視点情報: &フレーム視点,
    中心: [f64; 3],
    ずらし量: 大域ワールド位置,
    幅: u32,
    高さ: u32,
) -> Result<板の投影, String> {
    let 大域位置 = 大域ワールド位置::生成する(
        大域メートル::生成する(中心[0]),
        大域メートル::生成する(中心[1]),
        大域メートル::生成する(中心[2]),
    )
    .平行移動する(ずらし量);
    let 相対 = 大域位置
        .カメラ相対へ変換する(視点情報.カメラ大域位置)
        .map_err(|誤り| format!("板の中心をカメラ相対へ写せなかった: {誤り}"))?;
    let 相対座標 = [f64::from(相対.x().値()), f64::from(相対.y().値()), f64::from(相対.z().値())];
    let クリップ = 列優先で掛ける(視点情報.ビュー射影の組.ずらし無し().gpu境界用列優先配列(), 相対座標);
    if クリップ[3] <= f64::EPSILON {
        return Err("板の中心がカメラの後ろにある".to_string());
    }
    Ok(板の投影 {
        横: 画素番号へ直す(クリップ[0] / クリップ[3], 幅)?,
        縦: 画素番号へ直す(クリップ[1] / クリップ[3], 高さ)?,
        視線: 表面からカメラへの向き(相対座標)?,
    })
}

/// カメラ相対フレームの原点はカメラ自身であるため、表面からカメラへの向きは相対位置の逆向きである。
fn 表面からカメラへの向き(相対座標: [f64; 3]) -> Result<[f64; 3], String> {
    let 長さ二乗: f64 = 相対座標.iter().map(|値| 値 * 値).sum();
    if !長さ二乗.is_finite() || 長さ二乗 <= f64::EPSILON {
        return Err("板の中心がカメラの位置と重なっている".to_string());
    }
    let 逆長さ = 長さ二乗.sqrt().recip();
    Ok([-相対座標[0] * 逆長さ, -相対座標[1] * 逆長さ, -相対座標[2] * 逆長さ])
}

/// 正規化デバイス座標から画素番号を求める。左上の画素の中心が正規化デバイス座標の左上寄りに来る規約は
/// `sky_pixel::view_ray`の逆写像と同じである。
fn 画素番号へ直す(正規化デバイス座標: f64, 画素数: u32) -> Result<u32, String> {
    let 実数の位置 = (正規化デバイス座標 + 1.0) * 0.5 * f64::from(画素数);
    if !実数の位置.is_finite() || 実数の位置 < 0.0 {
        return Err(format!("板の中心が画面の外にある(正規化デバイス座標{正規化デバイス座標})"));
    }
    let 番号 = 切り捨てる(実数の位置);
    if 番号 >= 画素数 {
        return Err(format!("板の中心が画面の外にある(正規化デバイス座標{正規化デバイス座標})"));
    }
    Ok(番号)
}

/// 実数を超えない最大の整数。`as`を使わずに求めるため、2進で桁を上から確かめる。
fn 切り捨てる(値: f64) -> u32 {
    let mut 番号 = 0u32;
    let mut 刻み = 1u32 << 15;
    while 刻み > 0 {
        let 候補 = 番号 + 刻み;
        if f64::from(候補) <= 値 {
            番号 = 候補;
        }
        刻み >>= 1;
    }
    番号
}

/// GPU境界の列優先配列と、同次座標のwを1にした点との積。
fn 列優先で掛ける(行列: [[f32; 4]; 4], 位置: [f64; 3]) -> [f64; 4] {
    let ベクトル = [位置[0], 位置[1], 位置[2], 1.0];
    let mut 結果 = [0.0; 4];
    for (行, 値) in 結果.iter_mut().enumerate() {
        for (列, 成分) in ベクトル.iter().enumerate() {
            *値 += f64::from(行列[列][行]) * 成分;
        }
    }
    結果
}
