//! 注入した鏡面畳込みの中身を、参照先(縮小段の位置と面)から読み出す工程。受け取るのは解析入力と参照先、
//! 返すのはその参照が得る放射輝度である。GPUの標本と同じ結果を返すことがこの工程の責務である。
//!
//! 段の間を補間するのは、GPUが実数の段の位置で標本して隣り合う段を混ぜるためである。検収の板は粗さを
//! 整数の段へ正確に合わせてあるため実際には混ざらないが、混ざらないことを前提に置くと粗さを1つ変えただけで
//! 期待値が黙って崩れる。
//!
//! 面の中の位置を持ち回るのは、面の境界に近い参照を検収が拒めるようにするためである。境界の近くではGPUの
//! 補間が隣の面を混ぜるため、面ごとに違う色を置いた判定が成り立たない。

use blitz_render::cube_image::立方体の面;
use blitz_render::distant_environment::{遠方環境の解析入力, 鏡面畳込みの解析入力};

/// 鏡面畳込みのどこを参照したか。
pub(super) struct 鏡面の参照先 {
    pub(super) 面: 立方体の面,
    pub(super) 横位置: f64,   // 面の中の横位置。0以上1以下であり、0と1が面の端である
    pub(super) 縦位置: f64,   // 面の中の縦位置。横位置と同じく0以上1以下であり、0と1が面の端である
    pub(super) 段の位置: f64, // 縮小段の位置。整数なら1つの段、そうでなければ隣り合う2段の混ざりである
}

impl 鏡面の参照先 {
    /// 面の端からの余裕のうち小さいほう。境界に寄るほど0へ近づく。
    pub(super) fn 面の端からの余裕(&self) -> f64 {
        let 余裕 = |位置: f64| 位置.min(1.0 - 位置);
        余裕(self.横位置).min(余裕(self.縦位置))
    }
}

pub(super) fn 注入した鏡面の色(入力: &遠方環境の解析入力, 参照先: &鏡面の参照先) -> [f64; 3] {
    match 入力.鏡面畳込み() {
        鏡面畳込みの解析入力::段ごとの一様な色(色一覧) => 段を混ぜる(色一覧, 参照先.段の位置),
        鏡面畳込みの解析入力::面ごとの一様な色(色一覧) => 色一覧[面の添字(参照先.面)].map(f64::from),
    }
}

fn 段を混ぜる(色一覧: &[[f32; 3]], 段の位置: f64) -> [f64; 3] {
    let 最後の段 = 色一覧.len().saturating_sub(1);
    let 手前の添字 = 手前の段を探す(色一覧.len(), 段の位置);
    let 奥の添字 = (手前の添字 + 1).min(最後の段);
    let 比 = (段の位置 - 添字を実数へ(手前の添字)).clamp(0.0, 1.0);
    let 成分 = |軸: usize| {
        let 手前の値 = f64::from(色一覧[手前の添字][軸]);
        手前の値 + (f64::from(色一覧[奥の添字][軸]) - 手前の値) * 比
    };
    [成分(0), 成分(1), 成分(2)]
}

/// 段の位置を超えない最大の段番号。実数から整数への変換を`as`で書かずに済ませるため、段を順に見て決める。
fn 手前の段を探す(段数: usize, 段の位置: f64) -> usize {
    let mut 手前 = 0;
    for 添字 in 0..段数 {
        if 添字を実数へ(添字) <= 段の位置 {
            手前 = 添字;
        }
    }
    手前
}

fn 添字を実数へ(添字: usize) -> f64 {
    f64::from(u32::try_from(添字).unwrap_or_else(|_| panic!("縮小段の添字{添字}がu32に収まらない")))
}

fn 面の添字(面: 立方体の面) -> usize {
    usize::try_from(面.層番号()).unwrap_or_else(|_| panic!("立方体の面の層番号がusizeに収まらない"))
}
