//! 板1枚の期待放射輝度を、注入した解析入力と板の材質と視線から組み立てる工程。受け取るのは板と視線と太陽方向、
//! 返すのは線形の3成分と、その板が参照した縮小段と面である。
//!
//! 消費式そのものを書かず`blitz_render`の正本へ委ねるのは、シェーダーがその正本の写しだからである。
//! ここで式を書き直すと、写しの誤りと期待値の誤りが同じ不一致として出て見分けられない。
//!
//! 参照する縮小段と面をここで決めるのは、注入した鏡面の色が段と面で違うためである。GPUは反射方向と粗さから
//! 段と面を選んで標本するため、期待値の側も同じ選び方を再現しなければ値が合わない。

use blitz_render::atmosphere::太陽相対フレーム;
use blitz_render::cube_image::向きから面と面内位置を求める;
use blitz_render::distant_environment::consume::{
    垂直入射の反射率を求める, 拡散の取り分を求める, 粗さから縮小段の位置を求める, 粗さ対応の反射率を求める, 間接拡散の色を求める,
    間接鏡面の色を求める,
};
use blitz_render::distant_environment::derived::鏡面畳込みの解像度;

use super::plates::板の宣言;
use super::specular_lookup::{注入した鏡面の色, 鏡面の参照先};

/// 期待値と、その値を決めた参照先。参照先は面の境界へ寄っていないかの点検に使う。
pub(super) struct 板の期待 {
    pub(super) 放射輝度: [f64; 3],
    pub(super) 参照先: 鏡面の参照先,
}

/// 期待値の計算に要る材料。引数の列が伸びるのを避けて1つに束ねる。
pub(super) struct 期待の材料<'a> {
    pub(super) 解析入力: &'a blitz_render::distant_environment::遠方環境の解析入力,
    pub(super) 鏡面の解像度: 鏡面畳込みの解像度,
    pub(super) 太陽方向: [f64; 3],
}

pub(super) fn 期待を求める(材料: &期待の材料<'_>, 板: &板の宣言, 視線: [f64; 3]) -> 板の期待 {
    let 法線 = 板.法線;
    let 法線と視線の余弦 = 内積(法線, 視線).clamp(0.0, 1.0);
    let 反射方向 = 反射させる(視線, 法線, 法線と視線の余弦);
    let フレーム = 太陽相対フレーム::太陽方向から組む(材料.太陽方向);
    let 太陽相対の反射方向 = フレーム.ワールドの向きを写す(反射方向);
    let 段の位置 = 粗さから縮小段の位置を求める(板.粗さ, 材料.鏡面の解像度);
    let 参照先 = 参照先を決める(太陽相対の反射方向, 段の位置);

    let 垂直入射の反射率 = 垂直入射の反射率を求める(板.ベースカラー, 板.金属度);
    let 取り分 = 拡散の取り分を求める(粗さ対応の反射率を求める(法線と視線の余弦, 垂直入射の反射率, 板.粗さ), 板.金属度);
    let 拡散 = 間接拡散の色を求める(取り分, 材料.解析入力.拡散照度().map(f64::from), 板.ベースカラー);
    let 鏡面 = 間接鏡面の色を求める(
        注入した鏡面の色(材料.解析入力, &参照先),
        垂直入射の反射率,
        材料.解析入力.反射率積分表().map(f64::from),
    );
    板の期待 {
        放射輝度: [拡散[0] + 鏡面[0], 拡散[1] + 鏡面[1], 拡散[2] + 鏡面[2]],
        参照先,
    }
}

fn 参照先を決める(太陽相対の反射方向: [f64; 3], 段の位置: f64) -> 鏡面の参照先 {
    let (面, 横位置, 縦位置) = 向きから面と面内位置を求める(太陽相対の反射方向)
        .unwrap_or_else(|| panic!("反射方向が長さ0になった(板の法線と視線はどちらも単位ベクトルである)"));
    鏡面の参照先 {
        面,
        横位置,
        縦位置,
        段の位置,
    }
}

/// 表面から視線が来る向きに対する鏡面反射の向き。シェーダーの`reflect(-viewDir, normal)`と同じ値である。
fn 反射させる(視線: [f64; 3], 法線: [f64; 3], 法線と視線の余弦: f64) -> [f64; 3] {
    let 成分 = |添字: usize| 2.0 * 法線と視線の余弦 * 法線[添字] - 視線[添字];
    [成分(0), 成分(1), 成分(2)]
}

fn 内積(左: [f64; 3], 右: [f64; 3]) -> f64 {
    左[0] * 右[0] + 左[1] * 右[1] + 左[2] * 右[2]
}
