//! キャスター候補のカメラ距離分布のコンソール出力。`--report-caster-distance`が指定されたときだけ呼ばれる。
//! 出すのは帯の幅と帯別の3種の件数だけであり、どの距離で切るかの判定は行わない。
//!
//! 帯を距離でなく番号で並べるのは、帯の下限が「番号×帯の幅」で一意に決まり、1行が距離の文字列で長くならないためである。
//! 帯の幅を同じ報告の中で先に出すのは、番号から距離を読み戻す側がその値を持たないと帯を距離へ戻せないためである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」

use blitz_engine::キャスター距離分布;

/// 最終フレームのキャスター候補を、カメラからの距離の帯へ振り分けた分布。
/// 候補数は影を落とすかに依らず選別が距離を読んだ個体、和集合の可視数は1つ以上の距離区分へ影を落とした個体、
/// 距離区分別の可視数はその距離区分のシャドウパスが描く個体である。
/// 距離Dで切ったときに残る費用は距離区分別の可視数を帯Dまで足した値の比で、残るキャスター数は和集合を同じく足した値の比で読む。
pub(crate) fn キャスター距離分布を表示する(分布: &キャスター距離分布) {
    println!("  キャスター距離帯の幅メートル: {}", キャスター距離分布::帯の幅メートル);
    println!("  キャスター距離帯数: {}", キャスター距離分布::帯数);
    println!("  キャスター距離帯別の候補数: {}", 帯別を並べる(&分布.帯別の候補数()));
    println!("  キャスター距離帯別の和集合の可視数: {}", 帯別を並べる(&分布.帯別の和集合の可視数()));
    for (番号, 帯別) in 分布.帯別の距離区分別の可視数().iter().enumerate() {
        println!("  キャスター距離帯別の距離区分{番号}の可視数: {}", 帯別を並べる(帯別));
    }
}

/// 帯番号と件数の対を帯番号の昇順で並べた1行。件数が0の帯も落とさず出す。落とすと帯番号と距離の対応が読み手側で崩れる。
fn 帯別を並べる(帯別: &[u64]) -> String {
    let 並び: Vec<String> = 帯別.iter().enumerate().map(|(番号, 件数)| format!("{番号}={件数}")).collect();
    並び.join(" ")
}
