//! GPU資源の束縛にまつわる計器のコンソール出力。触れるのはセット別の束縛回数と材質資源表の要約の2行だけである。
//! 行の綴りは検収の`xtask/src/report_parse/extract.rs`が読む。

/// 直近のフレームでscene系のセット番号ごとにディスクリプタセットを束縛した回数。材質のセット(番号2)が
/// 材質やプリミティブの数で増えず、パスごと1回に収まっていることをこの行で見る。
pub(crate) fn セット別束縛回数を表示する(回数: [u32; 4]) {
    let 並び: Vec<String> = 回数.iter().enumerate().map(|(番号, 回数)| format!("{番号}={回数}")).collect();
    println!("  セット別ディスクリプタ束縛回数: {}", 並び.join(" "));
}

/// 公開中の資源表世代の版番号と中身の件数。テクスチャを1枚も持たない材質が何件あっても、常駐画像が
/// 正準フォールバックの3枚だけに収まることをこの行で見る。
pub(crate) fn 材質資源表の要約を表示する(要約: blitz_render::材質資源表の要約) {
    println!(
        "  材質資源表: 世代番号={} 材質件数={} 常駐画像枚数={}",
        要約.世代番号(),
        要約.材質件数(),
        要約.常駐画像枚数()
    );
}
