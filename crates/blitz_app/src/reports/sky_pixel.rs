//! 空の代表画素の照合報告。指定された画素について、読み戻した実機の画素値と、同じ向きの空の色をCPU正本から
//! 求め直した期待値を1行ずつ並べる。判定は`cargo xtask sky-time`がこの出力を読んで行う。
//!
//! これがスカイビューの参照側の写像(ワールドの視線からベイク済み画像の視線と単位位置を求める工程)の本番外の呼び出し元であり、
//! シェーダー内の写しが正本と一致していることを実機の絵で確かめる唯一の経路である。
//!
//! ポスト処理を外した実行を前提にする。スワップチェーンの形式がsRGBであるため、その構成の書き込みは
//! 「線形の放射輝度を0から1へ切り詰めてsRGB符号化した値」そのものになり、期待値を閉じた式で作れる。
//! ブルームとACESトーンマップを通す実行では、周囲の明るさが混ざって1画素の期待値が決まらない。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「検証の設計」

mod expected_radiance;
mod row;
mod srgb_encode;
mod view_ray;

use blitz_render::atmosphere::{
    スカイビュー表, スカイビュー観測条件, 多重散乱表, 大気のベイク済み画像の解像度, 天頂余弦, 透過率表
};
use blitz_render::読み戻し画像;

use crate::app::空の再現条件;
use crate::cli::画面画素位置;

/// 照合に要る材料。1フレームぶんの視点と読み戻し画像、それに空の再現条件を束ねる。
pub(crate) struct 照合の材料<'a> {
    pub(crate) 条件: 空の再現条件,
    pub(crate) 画像: &'a 読み戻し画像,
    /// クリップ座標からカメラ相対ワールドへ戻す行列。空パスの頂点段が使うものと同じ値である。
    pub(crate) 逆ビュー射影行列: [[f32; 4]; 4],
    /// カメラ相対フレームでのカメラの位置。頂点段が視線を作るときに参照する値である。
    pub(crate) カメラ相対位置: [f32; 3],
    pub(crate) 画素一覧: &'a [画面画素位置],
}

pub(crate) fn 代表画素を照合する(材料: &照合の材料<'_>) {
    match 照合する(材料) {
        Ok(()) => {}
        Err(理由) => println!("空代表画素 照合できなかった 理由={理由}"),
    }
}

fn 照合する(材料: &照合の材料<'_>) -> Result<(), String> {
    let 媒体 = 材料.条件.大気;
    let 解像度 = 大気のベイク済み画像の解像度::既定値();
    let 太陽天頂余弦 = 天頂余弦::生成する(材料.条件.太陽方向[1].clamp(-1.0, 1.0)).map_err(|誤り| 誤り.to_string())?;
    let 観測条件 = スカイビュー観測条件::生成する(材料.条件.空描画.観測高度(), 太陽天頂余弦).map_err(|誤り| 誤り.to_string())?;
    let 透過率表 = 透過率表::焼く(媒体.消散(), 解像度).map_err(|誤り| 誤り.to_string())?;
    let 多重散乱表 = 多重散乱表::焼く(&媒体, &透過率表, 解像度).map_err(|誤り| 誤り.to_string())?;
    let スカイビュー表 = スカイビュー表::焼く(&媒体, &透過率表, &多重散乱表, 解像度, 観測条件).map_err(|誤り| 誤り.to_string())?;
    let 期待の材料 = expected_radiance::期待の材料 {
        媒体: &媒体,
        スカイビュー表: &スカイビュー表,
        観測条件,
        空描画: 材料.条件.空描画,
        太陽方向: 材料.条件.太陽方向,
    };
    for (番号, 画素) in 材料.画素一覧.iter().enumerate() {
        let 視線 = view_ray::画素の視線を求める(材料, *画素)?;
        let 期待 = expected_radiance::期待を求める(&期待の材料, 視線)?;
        let 実測 = 材料
            .画像
            .ピクセル(画素.横, 画素.縦)
            .ok_or_else(|| format!("画素({}, {})が読み戻し画像の外にある", 画素.横, 画素.縦))?;
        row::行を出す(番号 + 1, *画素, &期待, [実測[0], 実測[1], 実測[2]]);
    }
    Ok(())
}
