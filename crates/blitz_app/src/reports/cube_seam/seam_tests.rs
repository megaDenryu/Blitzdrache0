//! 稜線の導出が立方体の位相と合っていることを確かめる。担うのは、12本の稜線がもれなく1度ずつ数えられること、
//! 隣接が対称であること、上下の面も4本ずつ稜線を持つことの3つである。
//!
//! 向かい合うテクセルの選び方は`correspondence_tests`が別に見る。こちらは面と面の関係だけを見る。

#![allow(clippy::unwrap_used)]

use blitz_render::cube_image::{立方体の全面, 立方体の面};

use super::edge_pairs::{全ての辺, 相手側の辺, 辺の隣接面};

#[test]
fn 稜線は12本あり重複しない() {
    let mut 組一覧 = Vec::new();
    for 面 in 立方体の全面 {
        for 辺 in 全ての辺 {
            let 隣 = 辺の隣接面(面, 辺);
            assert_ne!(隣, 面, "面{面:?}の辺{辺:?}が自分自身を指した");
            if 隣.層番号() > 面.層番号() {
                組一覧.push((面.層番号(), 隣.層番号()));
            }
        }
    }
    組一覧.sort_unstable();
    let 重複なし = {
        let mut 写し = 組一覧.clone();
        写し.dedup();
        写し
    };
    assert_eq!(組一覧.len(), 12, "稜線の本数が{}である", 組一覧.len());
    assert_eq!(重複なし.len(), 12, "同じ面の組が2度現れた");
}

#[test]
fn 隣接は対称である() {
    for 面 in 立方体の全面 {
        for 辺 in 全ての辺 {
            let 隣 = 辺の隣接面(面, 辺);
            assert_eq!(辺の隣接面(隣, 相手側の辺(隣, 面)), 面);
        }
    }
}

#[test]
fn 天頂と天底の面も4本ずつ稜線を持つ() {
    for 面 in [立方体の面::第二軸の正, 立方体の面::第二軸の負] {
        let 隣一覧: Vec<u32> = 全ての辺.into_iter().map(|辺| 辺の隣接面(面, 辺).層番号()).collect();
        assert!(!隣一覧.contains(&面.層番号()));
        assert!(!隣一覧.contains(&対向面の層番号(面)));
        assert_eq!(隣一覧.len(), 4);
    }
}

/// 立方体の面の並びは軸ごとに正・負が隣り合うため、対向面の層番号は自分の層番号の最下位ビットを反転した値である。
fn 対向面の層番号(面: 立方体の面) -> u32 {
    面.層番号() ^ 1
}
