//! 読み戻した立方体画像の1テクセルを取り出す工程と、2つのテクセルの相対差を測る工程。
//! 受け取るのは読み戻しの列と面と添字、返すのはRGBの3成分または成分ごとの相対差の最大である。
//!
//! 通し番号の求め方をここで書き直さずレンダラーの公開の関数へ委ねるのは、焼く側と読む側の並びが
//! 1つの正本から決まることを保つためである。

use blitz_render::cube_image::立方体の面;
use blitz_render::distant_environment::derived::立方体テクセルの通し番号;

pub(crate) fn 立方体のテクセル(読み戻し: &[[f32; 4]], 面: 立方体の面, 横: u32, 縦: u32, 一辺: u32) -> [f32; 3] {
    let 通し番号 = 立方体テクセルの通し番号(面, 横, 縦, 一辺);
    let Some(テクセル) = 読み戻し.get(通し番号) else {
        panic!("読み戻しの範囲外を参照した(層{} 横{横} 縦{縦} 一辺{一辺})", 面.層番号());
    };
    [テクセル[0], テクセル[1], テクセル[2]]
}

/// 成分ごとの相対差の最大。分母を2つの絶対値の大きい方に取るのは、0に近い成分で相対差が発散しないようにするためである。
/// どちらも0に近いときは差そのものが小さいため、下限を置いて絶対差の扱いへ落とす。
pub(crate) fn 相対差(左: [f32; 3], 右: [f32; 3]) -> f64 {
    let mut 最大 = 0.0_f64;
    for 添字 in 0..3 {
        let 左値 = f64::from(左[添字]);
        let 右値 = f64::from(右[添字]);
        let 分母 = 左値.abs().max(右値.abs()).max(1.0e-6);
        最大 = 最大.max((左値 - 右値).abs() / 分母);
    }
    最大
}
