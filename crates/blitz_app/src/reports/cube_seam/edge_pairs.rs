//! 立方体画像の面が持つ4つの辺と、その向こう側にある面を求める工程。受け取るのは面と辺、
//! 返すのは隣接する面または辺の上のテクセルの添字である。
//!
//! 12本の稜線を表に書き下ろさず導出するのは、書き下ろした表が面と向きの写像から独立してしまうためである。
//! 写像を変えたときに表だけが古いまま残ると、継ぎ目の検査が別の場所どうしを突き合わせて通ってしまう。
//!
//! 隣接する面は、辺の中点の向きから面の中心の向きを引いた差の主軸で決まる。差の主軸の成分は辺の向きの側が
//! 必ず大きくなるため、面の中心から辺へ出た先にある面がこれで一意に決まる。

use blitz_render::atmosphere::{向きから面と面内位置を求める, 立方体の面, 面と面内位置から向きを求める};

/// 面の4つの辺。名前は面内位置の目盛りで、その辺がどちら側にあるかを表す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 面の辺 {
    横の先頭,
    横の末尾,
    縦の先頭,
    縦の末尾,
}

pub(super) const 全ての辺: [面の辺; 4] = [面の辺::横の先頭, 面の辺::横の末尾, 面の辺::縦の先頭, 面の辺::縦の末尾];

impl 面の辺 {
    /// 辺の中点の面内位置。隣接する面を求めるのに使う。
    fn 中点の面内位置(self) -> (f64, f64) {
        match self {
            Self::横の先頭 => (0.0, 0.5),
            Self::横の末尾 => (1.0, 0.5),
            Self::縦の先頭 => (0.5, 0.0),
            Self::縦の末尾 => (0.5, 1.0),
        }
    }

    /// 辺の上の指定番目のテクセルの添字。番号は横の辺なら縦の添字、縦の辺なら横の添字に対応する。
    pub(super) fn 辺上の添字(self, 番号: u32, 一辺: u32) -> (u32, u32) {
        match self {
            Self::横の先頭 => (0, 番号),
            Self::横の末尾 => (一辺 - 1, 番号),
            Self::縦の先頭 => (番号, 0),
            Self::縦の末尾 => (番号, 一辺 - 1),
        }
    }
}

/// その辺の向こう側にある面。
pub(super) fn 辺の隣接面(面: 立方体の面, 辺: 面の辺) -> 立方体の面 {
    let (横, 縦) = 辺.中点の面内位置();
    let 辺の向き = 面と面内位置から向きを求める(面, 横, 縦);
    let 中心の向き = 面と面内位置から向きを求める(面, 0.5, 0.5);
    let 差 = [辺の向き[0] - 中心の向き[0], 辺の向き[1] - 中心の向き[1], 辺の向き[2] - 中心の向き[2]];
    let Some((隣, _, _)) = 向きから面と面内位置を求める(差) else {
        panic!("面{面:?}の辺{辺:?}の外向きが長さ0になった(面と向きの写像が壊れている)");
    };
    隣
}

/// 隣接する面の側から見て、この面と接している辺。隣り合う2つの面が共有する稜線は1本だけであるため、
/// 該当する辺は必ず1つに定まる。
pub(super) fn 相手側の辺(隣: 立方体の面, 元の面: 立方体の面) -> 面の辺 {
    let Some(辺) = 全ての辺.into_iter().find(|辺| 辺の隣接面(隣, *辺) == 元の面) else {
        panic!("面{隣:?}に面{元の面:?}と接する辺が無い(隣接の導出が対称でない)");
    };
    辺
}
