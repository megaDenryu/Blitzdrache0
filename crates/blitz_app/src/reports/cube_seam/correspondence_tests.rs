//! 稜線をはさんで向かい合うテクセルの選び方を確かめる。担うのは、側面どうしの対応が写像から手で導いた組と
//! 一致することと、どの稜線でも相手が2テクセル以内の角度にあることの2つである。
//!
//! 後者が対応の正しさの決め手である。対応を取り違えると相手は稜線に沿って遠く離れたテクセルになり、
//! 角度が数十度になる。正しければ稜線をはさんで半テクセルずつの位置にあり、角度はテクセル2つぶんに収まる。
//! 値の差で見る本番の判定と違い、この検査は焼いた中身に1つも依存しないため、天空放射輝度がどれだけ
//! 速く変わっても結論が動かない。

#![allow(clippy::unwrap_used)]

use blitz_render::atmosphere::{テクセル中心の面内位置, 立方体の全面, 立方体の面, 面と面内位置から向きを求める};

use super::edge_pairs::{全ての辺, 相手側の辺, 辺の隣接面};
use super::nearest_texel::辺の上で最も近い添字;

#[test]
fn 側面どうしの対応は写像から導いた組と一致する() {
    let 一辺 = 8;
    let 側面の輪 = [
        (立方体の面::第一軸の正, 立方体の面::第三軸の正),
        (立方体の面::第三軸の正, 立方体の面::第一軸の負),
        (立方体の面::第一軸の負, 立方体の面::第三軸の負),
        (立方体の面::第三軸の負, 立方体の面::第一軸の正),
    ];
    for (左の面, 右の面) in 側面の輪 {
        let 左の辺 = 相手側の辺(左の面, 右の面);
        for 縦 in 0..一辺 {
            let (横, 実際の縦) = 左の辺.辺上の添字(縦, 一辺);
            assert_eq!((横, 実際の縦), (0, 縦), "側面{左の面:?}の接する辺が横の先頭でない");
            let 相手 = 辺の上で最も近い添字(左の面, 横, 実際の縦, 右の面, 相手側の辺(右の面, 左の面), 一辺);
            assert_eq!(相手, (一辺 - 1, 縦), "側面{左の面:?}と{右の面:?}の対応が縦の添字を保っていない");
        }
    }
}

#[test]
fn 向かい合うテクセルは2テクセル以内の角度に収まる() {
    let 一辺 = 32;
    let テクセル1つぶんの角度 = 2.0 / f64::from(一辺);
    let 許す余弦 = (テクセル1つぶんの角度 * 2.0).cos();
    for 面 in 立方体の全面 {
        for 辺 in 全ての辺 {
            let 隣 = 辺の隣接面(面, 辺);
            let 隣の辺 = 相手側の辺(隣, 面);
            for 番号 in 0..一辺 {
                let (横, 縦) = 辺.辺上の添字(番号, 一辺);
                let (隣の横, 隣の縦) = 辺の上で最も近い添字(面, 横, 縦, 隣, 隣の辺, 一辺);
                let 余弦 = 内積(テクセルの向き(面, 横, 縦, 一辺), テクセルの向き(隣, 隣の横, 隣の縦, 一辺));
                assert!(
                    余弦 > 許す余弦,
                    "面{面:?}の辺{辺:?}の{番号}番目と面{隣:?}の相手の内積が{余弦}で、許す{許す余弦}を下回った"
                );
            }
        }
    }
}

fn テクセルの向き(面: 立方体の面, 横: u32, 縦: u32, 一辺: u32) -> [f64; 3] {
    面と面内位置から向きを求める(面, テクセル中心の面内位置(横, 一辺), テクセル中心の面内位置(縦, 一辺))
}

fn 内積(左: [f64; 3], 右: [f64; 3]) -> f64 {
    左[0] * 右[0] + 左[1] * 右[1] + 左[2] * 右[2]
}
