//! 稜線をはさんで向かい合うテクセルを、向きの近さで選ぶ工程。受け取るのは手前の面とテクセル、
//! 相手の面とその辺、返すのは相手の辺の上で向きが最も近いテクセルの添字である。
//!
//! 添字の対応表を持たないのは、稜線ごとに添字が増える向きが同じだったり逆だったりするためである。
//! 稜線をはさんだ2つのテクセルはどちらも稜線から半テクセルの位置にあり、稜線に沿った位置が同じ組が
//! 必ず1対1に対応するため、内積が最大の相手を選べば対応表と同じ組が得られる。

use blitz_render::atmosphere::{テクセル中心の面内位置, 立方体の面, 面と面内位置から向きを求める};

use super::edge_pairs::面の辺;

pub(super) fn 辺の上で最も近い添字(
    面: 立方体の面, 横: u32, 縦: u32, 隣: 立方体の面, 隣の辺: 面の辺, 一辺: u32
) -> (u32, u32) {
    let 手前の向き = テクセルの向き(面, 横, 縦, 一辺);
    let mut 最も近い = 隣の辺.辺上の添字(0, 一辺);
    let mut 最大の内積 = f64::NEG_INFINITY;
    for 番号 in 0..一辺 {
        let (隣の横, 隣の縦) = 隣の辺.辺上の添字(番号, 一辺);
        let 内積 = 内積を求める(手前の向き, テクセルの向き(隣, 隣の横, 隣の縦, 一辺));
        if 内積 > 最大の内積 {
            最大の内積 = 内積;
            最も近い = (隣の横, 隣の縦);
        }
    }
    最も近い
}

fn テクセルの向き(面: 立方体の面, 横: u32, 縦: u32, 一辺: u32) -> [f64; 3] {
    面と面内位置から向きを求める(面, テクセル中心の面内位置(横, 一辺), テクセル中心の面内位置(縦, 一辺))
}

fn 内積を求める(左: [f64; 3], 右: [f64; 3]) -> f64 {
    左[0] * 右[0] + 左[1] * 右[1] + 左[2] * 右[2]
}
