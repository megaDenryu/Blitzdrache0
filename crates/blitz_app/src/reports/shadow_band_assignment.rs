//! 影の距離区分をどう分けて走ったかをコンソールへ表示する。どの実行も起動時に1回出す。
//!
//! 出すのは、この分け方がカタログを読んだ後に決まるためである。世界級の遠景を持つ世界だけが名指しの境界へ移り、
//! 他の世界は実用分割のまま走る。分け方が変われば影の細かさが距離帯ごとに変わり絵が変わるので、どちらで走ったかを
//! 絵からでなく行から読めるようにしておく。検収は再配分の前後を突き合わせるとき、この行で対照と候補の条件を確かめる。
//!
//! 注意: 見出しの綴りは検収との契約であり、`cargo xtask conform`の綴りの台帳が読む側と結んでいる。

use blitz_render::cascade::{距離区分の分け方, 距離区分の割り当て};

pub(crate) fn 影の距離区分の分け方を表示する(割り当て: 距離区分の割り当て, 世界級の遠景がある: bool) {
    let 根拠 = if 世界級の遠景がある {
        "世界級の遠景あり"
    } else {
        "世界級の遠景なし"
    };
    println!(
        "影の距離区分の分け方: {} 根拠={根拠} 最大影距離={:.6} {}",
        分け方の呼び名(割り当て.分け方()),
        割り当て.最大影距離().値(),
        境界の綴り(割り当て.分け方())
    );
}

fn 分け方の呼び名(分け方: 距離区分の分け方) -> &'static str {
    match 分け方 {
        距離区分の分け方::実用分割(_) => "実用分割",
        距離区分の分け方::明示の境界(_) => "明示境界",
    }
}

/// 明示の境界は3つの距離をそのまま並べ、実用分割は境界を最大影距離から計算するため混合率だけを出す。
fn 境界の綴り(分け方: 距離区分の分け方) -> String {
    match 分け方 {
        距離区分の分け方::実用分割(混合率) => format!("混合率={:.6}", 混合率.値()),
        距離区分の分け方::明示の境界(境界) => {
            let 距離一覧 = 境界.距離一覧().map(|距離| format!("{:.6}", 距離.値()));
            format!("境界={}", 距離一覧.join("/"))
        }
    }
}
