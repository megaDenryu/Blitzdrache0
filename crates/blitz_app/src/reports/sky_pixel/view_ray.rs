//! 画素の中心からワールドの視線を復元する工程。受け取るのは画素の位置、返すのは単位化した視線である。
//!
//! 式は`shaders/sky_frame.slang`の頂点段と同じである。全画面三角形はクリップ座標のwが一定であるため、
//! 頂点で求めた向きの線形補間が画素ごとの厳密な向きになる。ここでは補間の結果を、その画素の中心の
//! 正規化デバイス座標から直に求める。

use super::照合の材料;
use crate::cli::画面画素位置;

pub(super) fn 画素の視線を求める(材料: &照合の材料<'_>, 画素: 画面画素位置) -> Result<[f64; 3], String> {
    let 幅 = f64::from(材料.画像.幅());
    let 高さ = f64::from(材料.画像.高さ());
    if f64::from(画素.横) >= 幅 || f64::from(画素.縦) >= 高さ {
        return Err(format!("画素({}, {})が読み戻し画像の外にある", 画素.横, 画素.縦));
    }
    // 画素の中心を取る。左上の画素の中心が正規化デバイス座標(-1 + 1/幅, -1 + 1/高さ)に来る。
    let 横ndc = (f64::from(画素.横) + 0.5) / 幅 * 2.0 - 1.0;
    let 縦ndc = (f64::from(画素.縦) + 0.5) / 高さ * 2.0 - 1.0;
    let 遠点 = 列優先で掛ける(材料.逆ビュー射影行列, [横ndc, 縦ndc, 1.0, 1.0]);
    if 遠点[3].abs() <= f64::EPSILON {
        return Err("逆ビュー射影が遠平面の点を無限遠へ写した".to_string());
    }
    let 視線 = [
        遠点[0] / 遠点[3] - f64::from(材料.カメラ相対位置[0]),
        遠点[1] / 遠点[3] - f64::from(材料.カメラ相対位置[1]),
        遠点[2] / 遠点[3] - f64::from(材料.カメラ相対位置[2]),
    ];
    単位化する(視線)
}

/// GPU境界の列優先配列との積。`配列[列][行]`の並びであるため、行ごとに列を渡って足す。
fn 列優先で掛ける(行列: [[f32; 4]; 4], ベクトル: [f64; 4]) -> [f64; 4] {
    let mut 結果 = [0.0; 4];
    for (行, 値) in 結果.iter_mut().enumerate() {
        for (列, 成分) in ベクトル.iter().enumerate() {
            *値 += f64::from(行列[列][行]) * 成分;
        }
    }
    結果
}

fn 単位化する(向き: [f64; 3]) -> Result<[f64; 3], String> {
    let 長さ二乗: f64 = 向き.iter().map(|値| 値 * 値).sum();
    if !長さ二乗.is_finite() || 長さ二乗 <= f64::EPSILON {
        return Err("復元した視線の長さが0になった".to_string());
    }
    let 逆長さ = 長さ二乗.sqrt().recip();
    Ok(向き.map(|値| 値 * 逆長さ))
}
