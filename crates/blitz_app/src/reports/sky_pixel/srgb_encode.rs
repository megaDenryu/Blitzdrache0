//! 線形放射輝度を0から1へ切り詰めたうえでsRGB8bit相当の値(0から255)へ符号化する。
//! 対象のフレームはポスト処理を外した実行であり、書き込みはこの符号化そのものになる
//! (参照: `sky_pixel`モジュール冒頭のコメント)。

pub(super) fn 線形をsrgb8bit相当へ変換する(線形値: f64) -> f64 {
    let 切り詰め = 線形値.clamp(0.0, 1.0);
    let srgb値 = if 切り詰め <= 0.003_130_8 {
        12.92 * 切り詰め
    } else {
        1.055 * 切り詰め.powf(1.0 / 2.4) - 0.055
    };
    srgb値.clamp(0.0, 1.0) * 255.0
}
