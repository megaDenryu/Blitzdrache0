//! 空の代表画素の照合が途中で止まる原因。この報告は絵の合否を決めず行を出すだけであり、
//! 止まったこと自体を1行として出して終わるため、起動エラーへは合流させずこの報告の中で閉じる。

use blitz_render::atmosphere::大気数学エラー;
use thiserror::Error;

#[derive(Debug, Error)]
pub(super) enum 空代表画素の照合エラー {
    #[error("期待値を求める大気の計算が成立しなかった: {0}")]
    大気の計算が成立しない(#[from] 大気数学エラー),

    #[error("画素({横}, {縦})が読み戻し画像の外にある")]
    画素が画像の外にある { 横: u32, 縦: u32 },

    #[error("逆ビュー射影が遠平面の点を無限遠へ写した")]
    遠平面の点が無限遠へ写った,

    #[error("復元した視線の長さが0になった")]
    視線の長さが零,
}
