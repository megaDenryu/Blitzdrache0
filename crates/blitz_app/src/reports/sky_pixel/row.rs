//! 空代表画素1件ぶんの比較行の書式。担当するのは「番号と画素位置とCPU正本のsRGB期待値、
//! 読み戻した実測値から、判定側が読める1行を出す」ことである。
//!
//! 書式を単独で持つのは、これが本番外の検収(`cargo xtask sky-time`)との機械可読な契約だからである。

use crate::cli::画面画素位置;

pub(super) fn 行を出す(番号: usize, 画素: 画面画素位置, 期待: &[f64; 3], 実測: [u8; 3]) {
    println!(
        "空代表画素 番号={番号} 横={} 縦={} 期待赤={:.4} 期待緑={:.4} 期待青={:.4} 実測赤={} 実測緑={} 実測青={}",
        画素.横, 画素.縦, 期待[0], 期待[1], 期待[2], 実測[0], 実測[1], 実測[2]
    );
}
