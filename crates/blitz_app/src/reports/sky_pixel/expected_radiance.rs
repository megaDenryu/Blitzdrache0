//! 視線からスカイビューのベイク済み画像を参照し直し、空パスのGPUシェーダーと同じ式で線形放射輝度を組み立てて
//! sRGB8bit相当へ符号化する工程。受け取るのはワールドの視線、返すのはその画素の期待sRGB値である。
//!
//! 太陽円盤の項は含まない。円盤は視線が太陽そのものへ向く画素だけに掛かる別項であり、代表画素は
//! 天頂・地平線直上など円盤から外れた向きを選ぶ運用に委ねている(呼び出し元の`cargo xtask sky-time`が選ぶ)。
//! 円盤そのものの画素検収は読み戻し画像の明るさから別に数える。
//! 参照: `shaders/sky_atmosphere.slang`

use blitz_engine::sky::空描画方針;
use blitz_render::atmosphere::{
    スカイビューのベイク済み画像の単位位置を求める, スカイビュー表, スカイビュー観測条件,
    ワールドの視線からスカイビューのベイク済み画像の視線を求める, 大気散乱媒体,
};

use super::srgb_encode::線形をsrgb8bit相当へ変換する;

/// 期待値の計算に要る材料。引数の列が伸びるのを避けて1つに束ねる。
pub(super) struct 期待の材料<'a> {
    pub(super) 媒体: &'a 大気散乱媒体,
    pub(super) スカイビュー表: &'a スカイビュー表,
    pub(super) 観測条件: スカイビュー観測条件,
    pub(super) 空描画: 空描画方針,
    pub(super) 太陽方向: [f32; 3],
}

pub(super) fn 期待を求める(材料: &期待の材料<'_>, 視線: [f64; 3]) -> Result<[f64; 3], String> {
    let 太陽方向 = 材料.太陽方向.map(f64::from);
    let ベイク済み画像視線 = ワールドの視線からスカイビューのベイク済み画像の視線を求める(視線, 太陽方向).map_err(|誤り| 誤り.to_string())?;
    let 観測半径 = f64::from(材料.観測条件.観測半径(材料.媒体.消散()).値());
    let [横位置, 縦位置] = スカイビューのベイク済み画像の単位位置を求める(材料.媒体.消散(), 観測半径, ベイク済み画像視線);
    let 標本 = 材料.スカイビュー表.単位位置から標本を参照する(横位置, 縦位置);

    let 太陽放射照度 = f64::from(材料.空描画.太陽放射照度());
    let 夜空放射輝度 = 材料.空描画.夜空放射輝度().成分();
    let mut 線形放射輝度 = [0.0_f64; 3];
    for 添字 in 0..3 {
        線形放射輝度[添字] = (標本[添字] * 太陽放射照度 + f64::from(夜空放射輝度[添字])).max(0.0);
    }

    Ok(線形放射輝度.map(線形をsrgb8bit相当へ変換する))
}
