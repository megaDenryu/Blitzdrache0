//! CPU正本の符号値列とGPUが書いた符号値列の突き合わせ。受け取るのは同じ寸法の2つの並び、返すのは
//! 誤差の代表値である。合否は判定せず、判定は入口(`cargo xtask local-visibility`)が行う。
//!
//! 全画素のバイト一致を課さないのは、slang写しが単精度で組まれ、CPU正本も単精度で組みながら中間の一部だけを
//! 倍精度で作るためである。丸めの差は最下位の符号値に現れる。代わりに最大絶対誤差と大きい側の代表誤差を出し、
//! 入口が明示の許容と比べる。
//!
//! 代表誤差を補間せずに採るのは、実在の誤差そのものを選ぶためである。補間すると、
//! どの画素にも起きていない誤差の値が報告に載る。
//!
//! `大きい側の代表誤差`が指すのは95パーセンタイル値である。最大絶対誤差だけでは、1画素の外れ値が
//! 面全体の食い違いを代表してしまうため、その1画素に引きずられない代表値をもう1つ並べる。

use blitz_math::{パーセンタイル順位, 昇順に並べた標本列, 順位から添字を選ぶ規則};

/// この突き合わせが読む順位と、添字を選ぶ規則。寄せる前からこの規則であり、報告の値を動かさないために変えない。
const 代表誤差の順位: f32 = 95.0;
const 添字を選ぶ規則: 順位から添字を選ぶ規則 = 順位から添字を選ぶ規則::件数を基準にした切り上げの1つ手前;

/// 突き合わせの代表値。単位はすべて8ビット無符号正規化の符号値である。
pub(crate) struct 突き合わせの結果 {
    pub(crate) 画素数: usize,
    pub(crate) 一致画素数: usize,
    pub(crate) 最大絶対誤差: u16,
    pub(crate) 大きい側の代表誤差: u16,
}

/// 前提: 2つの並びは同じ寸法から作られており、要素数が等しい。等しくないことは呼び出し元の組み立ての誤りである。
pub(crate) fn 突き合わせる(正本: &[u8], 写し: &[u8]) -> 突き合わせの結果 {
    if 正本.len() != 写し.len() {
        panic!("突き合わせる2つの並びの要素数が違う(正本{}件 写し{}件)", 正本.len(), 写し.len());
    }
    let mut 誤差一覧: Vec<u16> = 正本.iter().zip(写し.iter()).map(|(&正, &写)| u16::from(正.abs_diff(写))).collect();
    let 標本列 = 昇順に並べた標本列::並べ替えて生成する(&mut 誤差一覧);
    突き合わせの結果 {
        画素数: 標本列.件数(),
        一致画素数: 標本列.昇順の値一覧().iter().filter(|&&誤差| 誤差 == 0).count(),
        最大絶対誤差: 標本列.最大().unwrap_or(0),
        大きい側の代表誤差: 標本列.パーセンタイル値を求める(パーセンタイル順位::百分率から生成する(代表誤差の順位), 添字を選ぶ規則).unwrap_or(0),
    }
}
