//! CPU正本の符号値列とGPUが書いた符号値列の突き合わせ。受け取るのは同じ寸法の2つの並び、返すのは
//! 誤差の代表値である。合否は判定せず、判定は入口(`cargo xtask local-visibility`)が行う。
//!
//! 全画素のバイト一致を課さないのは、slang写しが単精度で組まれ、CPU正本も単精度で組みながら中間の一部だけを
//! 倍精度で作るためである。丸めの差は最下位の符号値に現れる。代わりに最大絶対誤差と第95百分位の誤差を出し、
//! 入口が明示の許容と比べる。
//!
//! p95を最近傍順位法で採るのは、標本を補間せず実在の誤差そのものを選ぶためである。補間すると、
//! どの画素にも起きていない誤差の値が報告に載る。

/// 突き合わせの代表値。単位はすべて8ビット無符号正規化の符号値である。
pub(crate) struct 突き合わせの結果 {
    pub(crate) 画素数: usize,
    pub(crate) 一致画素数: usize,
    pub(crate) 最大絶対誤差: u16,
    pub(crate) 第95百分位の誤差: u16,
}

/// 前提: 2つの並びは同じ寸法から作られており、要素数が等しい。等しくないことは呼び出し元の組み立ての誤りである。
pub(crate) fn 突き合わせる(正本: &[u8], 写し: &[u8]) -> 突き合わせの結果 {
    if 正本.len() != 写し.len() {
        panic!("突き合わせる2つの並びの要素数が違う(正本{}件 写し{}件)", 正本.len(), 写し.len());
    }
    let mut 誤差一覧: Vec<u16> = 正本.iter().zip(写し.iter()).map(|(&正, &写)| u16::from(正.abs_diff(写))).collect();
    誤差一覧.sort_unstable();
    突き合わせの結果 {
        画素数: 誤差一覧.len(),
        一致画素数: 誤差一覧.iter().filter(|&&誤差| 誤差 == 0).count(),
        最大絶対誤差: 誤差一覧.last().copied().unwrap_or(0),
        第95百分位の誤差: 最近傍順位の第95百分位(&誤差一覧),
    }
}

/// 昇順に並んだ誤差の第95百分位。順位は1始まりの切り上げで採り、空の並びでは0を返す。
fn 最近傍順位の第95百分位(昇順の誤差: &[u16]) -> u16 {
    if 昇順の誤差.is_empty() {
        return 0;
    }
    let 順位 = (昇順の誤差.len() * 95).div_ceil(100).max(1);
    昇順の誤差.get(順位 - 1).copied().unwrap_or(0)
}
