//! 検収が焼かせる合成深度の形の語彙と、その形ごとの寸法。触れる状態を持たず、担うのは名前と場面の対応を
//! 1箇所へ置くことだけである。
//!
//! 4つの形は`_doc/設計/放射輝度問い合わせ階層.md`「IIa-2の実装」が挙げた性質の対に揃えてある。平面は遮蔽が
//! 起きない形、段差は片側だけが暗くなる形、球は凸で偽の遮蔽が出ない形、凹面は法線が連続に変わりながら
//! 遮蔽が生まれる形である。
//!
//! 寸法を選ぶときは、遮蔽の判定が使うバイアスと半径の境界から余白を取る。境界の上に載る画素を突き合わせの
//! 標本にすると、単精度と倍精度の差が判定の裏返りとして現れ、可視度が標本1本ぶん(標本数16なら16符号値)飛ぶ。
//! 段差の奥行きの差0.6メートルは遮蔽半径0.5メートルの内側であり、凹面の底から縁までの落差も同じ尺度に収めてある。

use blitz_math::{メートル, 逆メートル};
use blitz_render::local_visibility::{合成深度の場面, 局所可視性エラー};

/// 検収が名指しできる形。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 合成深度の形 {
    平面,
    段差,
    球,
    凹面,
}

impl 合成深度の形 {
    /// 報告と入口が同じ語で読み書きするための名前。
    pub(crate) fn 名前(self) -> &'static str {
        match self {
            Self::平面 => "平面",
            Self::段差 => "段差",
            Self::球 => "球",
            Self::凹面 => "凹面",
        }
    }

    /// この形の場面。寸法の値域はCPU正本の生成の入口が確かめる。
    pub(crate) fn 場面を作る(self) -> Result<合成深度の場面, 局所可視性エラー> {
        match self {
            Self::平面 => 合成深度の場面::平面(メートル::生成する(3.0), 0.5),
            Self::段差 => 合成深度の場面::段差(メートル::生成する(3.0), メートル::生成する(3.6), 段差の境界の横位置),
            Self::球 => 合成深度の場面::球(メートル::生成する(3.0), メートル::生成する(1.0)),
            Self::凹面 => 合成深度の場面::凹面(メートル::生成する(3.0), 逆メートル::生成する(1.2)),
        }
    }
}

/// 段差の境界を画面の中ほどへ置く横位置。左右のどちらにも、遮蔽半径の影響が届かない列が十分に残る幅を取る。
const 段差の境界の横位置: u32 = 640;
