//! GPUが書いた符号値の並びから、面の性質を読む集計。受け取るのは符号値の並びと寸法、返すのは代表値である。
//!
//! CPU正本の性質検査と同じ枠組みで採るのは、正本で立った性質がGPUでも残ることを同じ物差しで見るためである
//! (`crates/blitz_render/src/local_visibility/local_visibility_tests/`)。最小値と隣接差だけでは足りず、
//! 面全体を同じ値で返す実装でも通ってしまうため、可視度の幅と、底と肩と縁の大小の並びを別に採る。
//!
//! 隣り合う組を横と縦の両方で数えるのは、法線が縦にも向きを変える面で、接基底の組み方の飛びが縦の並びにだけ
//! 現れることがあるためである。横だけの集計はそれを1つも捉えない。
//!
//! 底と肩と縁の位置は正本の性質検査と同じ取り方にしてある(中央行の中央・中央から幅の8分の1だけ外側・
//! 右端から3画素内側)。位置がずれると、正本で立った並びがGPUでも残っているかを同じ物差しで読めない。

use blitz_render::local_visibility::画像の寸法;

/// 面1枚ぶんの代表値。単位はすべて8ビット無符号正規化の符号値である。
pub(crate) struct 面の性質 {
    pub(crate) 最小符号値: u8,
    pub(crate) 符号値の幅: u16,
    pub(crate) 中央行の底: u8,
    pub(crate) 中央行の肩: u8,
    pub(crate) 中央行の縁: u8,
    pub(crate) 横の最大隣接差: u16,
    pub(crate) 縦の最大隣接差: u16,
}

/// 前提: 符号値の並びは寸法の画素数と同じ要素数を持ち、行優先である。
pub(crate) fn 面の性質を読む(符号値: &[u8], 寸法: 画像の寸法) -> 面の性質 {
    let 読む = |横: u32, 縦: u32| 符号値[寸法.通し番号(横, 縦)];
    let 中央の縦 = 寸法.高さ() / 2;
    面の性質 {
        最小符号値: 符号値.iter().copied().min().unwrap_or(0),
        符号値の幅: u16::from(符号値.iter().copied().max().unwrap_or(0)) - u16::from(符号値.iter().copied().min().unwrap_or(0)),
        中央行の底: 読む(寸法.幅() / 2, 中央の縦),
        中央行の肩: 読む(寸法.幅() / 2 + 寸法.幅() / 8, 中央の縦),
        中央行の縁: 読む(寸法.幅() - 3, 中央の縦),
        横の最大隣接差: 横の隣接差の最大(符号値, 寸法),
        縦の最大隣接差: 縦の隣接差の最大(符号値, 寸法),
    }
}

fn 横の隣接差の最大(符号値: &[u8], 寸法: 画像の寸法) -> u16 {
    let mut 最大 = 0;
    for 縦 in 0..寸法.高さ() {
        for 横 in 1..寸法.幅() {
            let 差 = 符号値[寸法.通し番号(横, 縦)].abs_diff(符号値[寸法.通し番号(横 - 1, 縦)]);
            最大 = 最大.max(u16::from(差));
        }
    }
    最大
}

fn 縦の隣接差の最大(符号値: &[u8], 寸法: 画像の寸法) -> u16 {
    let mut 最大 = 0;
    for 縦 in 1..寸法.高さ() {
        for 横 in 0..寸法.幅() {
            let 差 = 符号値[寸法.通し番号(横, 縦)].abs_diff(符号値[寸法.通し番号(横, 縦 - 1)]);
            最大 = 最大.max(u16::from(差));
        }
    }
    最大
}
