//! 同じ寸法の2枚のHDR画像の成分ごとの差を数え上げる工程。受け取るのは2枚、返すのは最大差・平均差・一致しない画素数である。
//!
//! 独立した工程にするのは、静止カメラの安定化の観測と、無効化直後の突き合わせが同じ数え上げを使うためである。
//! 片方だけが数え方を変えると、2つの行の値を並べて読む根拠が消える。

use blitz_render::HDR読み戻し画像;

/// 1度の走査で採る3つの量。
pub(super) struct 差の要約 {
    pub(super) 最大: f32,               // 成分ごとの差の絶対値の最大
    pub(super) 平均: f64,               // 成分ごとの差の絶対値の平均
    pub(super) 一致しない画素数: usize, // 4成分のどれかが1ビットでも違う画素の数
}

/// 前提: 2枚は同じ寸法である。寸法が違う組み合わせを作れるのは呼び出し側の配線の誤りであり、
/// 短い側の長さで走査を打ち切ると差が小さく出て検収が通ってしまうため、ここで名指しして落とす。
pub(super) fn 求める(左: &HDR読み戻し画像, 右: &HDR読み戻し画像) -> 差の要約 {
    if 左.幅() != 右.幅() || 左.高さ() != 右.高さ() {
        panic!("突き合わせる2枚の寸法が違う({}x{}と{}x{})", 左.幅(), 左.高さ(), 右.幅(), 右.高さ());
    }
    let mut 要約 = 差の要約 {
        最大: 0.0,
        平均: 0.0,
        一致しない画素数: 0,
    };
    let mut 総和 = 0.0_f64;
    let mut 成分数 = 0_u32;
    for (左の画素, 右の画素) in 左.成分列().chunks_exact(4).zip(右.成分列().chunks_exact(4)) {
        let mut 一致した = true;
        for (左の値, 右の値) in 左の画素.iter().zip(右の画素.iter()) {
            let 差 = (左の値 - 右の値).abs();
            要約.最大 = 要約.最大.max(差);
            総和 += f64::from(差);
            成分数 = 成分数.saturating_add(1);
            if 左の値 != 右の値 {
                一致した = false;
            }
        }
        if !一致した {
            要約.一致しない画素数 += 1;
        }
    }
    if 成分数 > 0 {
        要約.平均 = 総和 / f64::from(成分数);
    }
    要約
}
