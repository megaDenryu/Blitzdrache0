//! 再構成後の画像1枚を1つの整数へ畳む工程。受け取るのは画像、返すのは64ビットの要約値である。
//!
//! 画像そのものを2実行ぶん残して比べないのは、決定性の判定に要るのが「同じか違うか」だけだからである。
//! 1枚が十数メガバイトあり、2実行ぶんを残すと入口が画素の突き合わせのための保管を持つことになる。
//!
//! 注意: 単精度のビット列をそのまま畳む。値でなくビットで畳むのは、非数の画素が現れたときに2実行で
//! 同じビット列であることまで見るためである。値の比較では非数どうしが常に不一致になり、決定性を判定できない。

use blitz_render::HDR読み戻し画像;

/// 畳み込みの初期値と乗数。FNV-1aの64ビットの定数である。
const 初期値: u64 = 0xcbf2_9ce4_8422_2325;
const 乗数: u64 = 0x0000_0100_0000_01b3;

pub(super) fn 求める(画像: &HDR読み戻し画像) -> u64 {
    let mut 値 = 初期値;
    for 成分 in 画像.成分列() {
        for バイト in 成分.to_bits().to_le_bytes() {
            値 ^= u64::from(バイト);
            値 = 値.wrapping_mul(乗数);
        }
    }
    値
}
