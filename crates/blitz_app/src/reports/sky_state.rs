//! 天空状態表の報告。ウィンドウもレンダラーも作らず、代表時刻の天空状態を機械可読な行として標準出力へ出す。
//! これが空と太陽方針の本番の呼び出し元であり、判定は`cargo xtask sky-state`がこの出力を読んで行う。
//! 検収が求める決定性と日境界の循環を出力から確かめられるよう、同じ代表時刻について4つの系列を出す。

mod report_error;
mod representative;
mod row;

use std::process::ExitCode;

use blitz_engine::sky::{天空状態を導出する, 空と太陽の方針};
use blitz_engine::time::世界時刻;
use blitz_math::大域秒;

use report_error::天空状態報告エラー;
use representative::代表時刻;

/// 同じ代表時刻について出す系列。再導出は決定性、前日と翌日は日境界の循環をそれぞれ確かめるためにある。
const 系列一覧: [(&str, f64); 4] = [("初回", 0.0), ("再導出", 0.0), ("前日", -1.0), ("翌日", 1.0)];

pub(crate) fn 天空状態表を出す() -> ExitCode {
    match 報告する() {
        Ok(()) => ExitCode::SUCCESS,
        Err(誤り) => {
            eprintln!("天空状態報告に失敗した: {誤り}");
            ExitCode::FAILURE
        }
    }
}

fn 報告する() -> Result<(), 天空状態報告エラー> {
    let 方針 = 空と太陽の方針::既定値();
    let 一日の秒数 = f64::from(方針.天球().一日の長さ().秒数().値());
    println!(
        "天空状態報告 一日の秒数={一日の秒数} 緯度度={} 太陽赤緯度={} 薄明帯の幅度={}",
        方針.天球().緯度().値().to_degrees(),
        方針.天球().太陽赤緯().値().to_degrees(),
        方針.昼夜().薄明帯の幅().値().to_degrees()
    );
    for 代表 in representative::代表時刻列を作る(方針.天球().一日の長さ())? {
        系列を出す(&代表, 一日の秒数, &方針)?;
    }
    Ok(())
}

fn 系列を出す(代表: &代表時刻, 一日の秒数: f64, 方針: &空と太陽の方針) -> Result<(), 天空状態報告エラー> {
    for (系列, 日数) in 系列一覧 {
        let 時刻 = 日をずらす(代表.時刻, 一日の秒数 * 日数)?;
        let 一日内時刻 = 時刻.一日内時刻へ(方針.天球().一日の長さ())?;
        let 状態 = 天空状態を導出する(時刻, 方針)?;
        row::行を出す(系列, 代表.名前, 時刻, 一日内時刻, &状態);
    }
    Ok(())
}

fn 日をずらす(時刻: 世界時刻, ずれ秒: f64) -> Result<世界時刻, 天空状態報告エラー> {
    Ok(時刻.進めた時刻(大域秒::生成する(ずれ秒))?)
}
