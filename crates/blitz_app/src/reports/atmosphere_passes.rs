//! 大気のベイク済み画像生成パスの実行数の報告。受け取るのは記録、返す代わりに機械可読な行を標準出力へ出す。
//!
//! フレームごとの本数を1行へ並べるのは、更新判定の期待(初回は4本・条件が変わらないフレームは0本・
//! カメラだけが動くフレームは1本・太陽が動くフレームは2本)がフレームの並びとして現れるためである。
//! 判定は`cargo xtask sky-lut`がこの行を読んで行う。
//!
//! 間接照明の行を同じ報告に並べるのは、どちらも「そのフレームで焼き直したか」を数える同じ種類の計器であり、
//! 大気を焼くフレームと遠方環境を焼くフレームの対応を1つの出力で突き合わせられるようにするためである。

use blitz_render::indirect_lighting::焼き上げ本数の見込み;
use blitz_render::{大気のベイク済み画像生成パス数の記録, 間接照明生成パス数の記録};

pub(crate) fn 大気のベイク済み画像生成パス数を表示する(記録: &大気のベイク済み画像生成パス数の記録) {
    let 列: Vec<String> = 記録.先頭フレームの列().iter().map(u32::to_string).collect();
    println!(
        "大気のベイク済み画像生成パス数 数えたフレーム数={} 総数={} 列の長さ={} 列={}",
        記録.数えたフレーム数(),
        記録.生成パスの総数(),
        列.len(),
        列.join(",")
    );
}

/// 間接照明の表現の生成パス数の報告。定数近似の契約では焼き直したフレーム数も総数も0になる。
pub(crate) fn 間接照明生成パス数を表示する(記録: &間接照明生成パス数の記録) {
    println!(
        "間接照明生成パス数 数えたフレーム数={} 焼き直したフレーム数={} 総数={}",
        記録.数えたフレーム数(),
        記録.焼き直したフレーム数(),
        記録.生成パスの総数()
    );
}

/// 1フレームに積む本数の見込み。検収はこの2つの合計と数えたフレーム数から条件ごとの期待を組み立てる。
/// 見込みを実測と同じ出力へ並べるのは、期待する本数を検収側で組み立てると、本番のレンダーグラフが誤った
/// 本数を積んでも検収が通ってしまうためである(参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Ic-3bの実装」)。
pub(crate) fn 間接照明生成パス数の見込みを表示する(見込み: Option<焼き上げ本数の見込み>) {
    match 見込み {
        Some(見込み) => println!(
            "間接照明生成パス数の見込み 契約=遠方環境 初回の合計={} 焼き直しの合計={}",
            見込み.初回に焼くフレーム.合計(),
            見込み.焼き直すフレーム.合計()
        ),
        None => println!("間接照明生成パス数の見込み 契約=定数近似"),
    }
}
