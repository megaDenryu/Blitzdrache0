//! 点光源の影の記録の内訳のコンソール出力。`--report-draw-issue`が指定されたときだけ呼ばれる。
//! 行の綴りは検収の`xtask/src/report_parse.rs`が読むため、既存の行を書き換えるとそちらも同時に直す必要がある。
//!
//! 描画発行の内訳と別に出すのは、点光源の影が可視ID列を1つも通らず、パス別の表と行の形が違うためである。

/// 最終フレームの点光源の影の記録の内訳。面ごとの絞りが判定した数と通した数の比が、絞りが落とした割合である。
/// 灯を1件も持たない世界では4つとも0であり、その0が「点光源の影のパスを1本も積んでいない」ことを示す。
pub(crate) fn 点光源の影の記録内訳を表示する(内訳: &blitz_render::点光源の影の記録内訳) {
    println!("点光源の影の記録内訳(最終フレーム):");
    println!("  点光源の影の記録した面の数: {}", 内訳.記録した面の数());
    println!("  点光源の影の絞りが判定した発行数: {}", 内訳.面ごとの絞りが判定した発行数());
    println!("  点光源の影の絞りを通った発行数: {}", 内訳.絞りを通った発行数());
    println!("  点光源の影の描画発行数: {}", 内訳.描画の発行数());
}
