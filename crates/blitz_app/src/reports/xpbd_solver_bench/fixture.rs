//! 計測の題材: 指定のグラフの種別から拘束グラフを作り、方式に応じた前計算(グラフ彩色・隣接表)を済ませた組。
//! グラフ彩色の方式では拘束を色順に並べ替えたグラフを持ち、GPUの拘束バッファも参照計算もその並びを使う。
//! 生成と前計算の所要時間を測って持つのは、彩色の前計算の費用が動的な拘束集合への適用しやすさの評価軸だからである。
//! 物性の値は固定である(粒子間隔5センチメートル・1点10グラム・コンプライアンス5ミリメートル毎ニュートン)。
//! コンプライアンスを0でなく正にするのは、刻み依存量α̃が有効逆質量の約1割になり、乗数の項が反復の式へ効く条件で測るためである。

use std::time::Instant;

use blitz_math::{メートル, 逆キログラム};
use blitz_render::xpbd_solver_bench_probe::{XPBD並列方式, XPBD彩色の区間, XPBD計測素材};
use blitz_sim::constraint_graph::{
    グラフ彩色, 不規則な拘束グラフを作る, 不規則グラフの仕様, 拘束グラフ, 点ごとの拘束の隣接表, 規則格子の仕様, 規則格子の拘束グラフを作る,
};
use blitz_sim::xpbd_gpu_layout;
use blitz_sim::コンプライアンス;

use crate::cli::{XPBD並列方式計測の指定, XPBD計測のグラフの種別};
use crate::error::起動エラー;

const 粒子間隔: f32 = 0.05;
const 一点の逆質量: f32 = 100.0;
const コンプライアンスの値: f32 = 0.005;
const 不規則の種: u64 = 20260902;
const 不規則の立方体の一辺: f32 = 2.0;

pub(super) struct 計測の題材 {
    pub(super) グラフ: 拘束グラフ,
    pub(super) 色の区間一覧: Vec<XPBD彩色の区間>,
    pub(super) 隣接表: 点ごとの拘束の隣接表,
    pub(super) 生成ミリ秒: f64,
    pub(super) 前計算ミリ秒: f64,
}

pub(super) fn 題材を作る(指定: &XPBD並列方式計測の指定) -> Result<計測の題材, 起動エラー> {
    let 逆質量 = 逆キログラム::生成する(一点の逆質量)?;
    let コンプライアンス = コンプライアンス::生成する(コンプライアンスの値)?;
    let 生成の開始 = Instant::now();
    let 元のグラフ = match 指定.グラフ {
        XPBD計測のグラフの種別::規則格子 => 規則格子の拘束グラフを作る(&規則格子の仕様 {
            点の数: 指定.点の数,
            粒子間隔: メートル::生成する(粒子間隔),
            一点の逆質量: 逆質量,
            コンプライアンス,
        })?,
        XPBD計測のグラフの種別::不規則 => 不規則な拘束グラフを作る(&不規則グラフの仕様 {
            点の数: 指定.点の数,
            種: 不規則の種,
            立方体の一辺: メートル::生成する(不規則の立方体の一辺),
            一点の逆質量: 逆質量,
            コンプライアンス,
        })?,
    };
    let 生成ミリ秒 = 生成の開始.elapsed().as_secs_f64() * 1000.0;
    let 前計算の開始 = Instant::now();
    let (グラフ, 色の区間一覧) = match 指定.方式 {
        XPBD並列方式::グラフ彩色 => {
            let 彩色 = グラフ彩色::生成する(&元のグラフ);
            let 区間一覧 = 彩色
                .色の区間一覧()
                .iter()
                .map(|区間| XPBD彩色の区間 {
                    開始: 区間.開始.値(),
                    本数: 区間.本数,
                })
                .collect();
            (彩色.並べ替えたグラフ().clone(), 区間一覧)
        }
        XPBD並列方式::原子加算 | XPBD並列方式::二段階 => (元のグラフ, Vec::new()),
    };
    let 隣接表 = 点ごとの拘束の隣接表::生成する(&グラフ);
    Ok(計測の題材 {
        グラフ,
        色の区間一覧,
        隣接表,
        生成ミリ秒,
        前計算ミリ秒: 前計算の開始.elapsed().as_secs_f64() * 1000.0,
    })
}

impl 計測の題材 {
    pub(super) fn 素材にする(&self) -> Result<XPBD計測素材, 起動エラー> {
        Ok(XPBD計測素材::生成する(
            xpbd_gpu_layout::点の状態バイト列にする(&self.グラフ),
            xpbd_gpu_layout::拘束の引数バイト列にする(&self.グラフ),
            xpbd_gpu_layout::隣接の区間バイト列にする(&self.隣接表),
            xpbd_gpu_layout::隣接の項目バイト列にする(&self.隣接表),
            self.色の区間一覧.clone(),
            usizeの個数をu32の数へ変換する(self.グラフ.点の数()),
            usizeの個数をu32の数へ変換する(self.グラフ.拘束の数()),
        )?)
    }
}

fn usizeの個数をu32の数へ変換する(値: usize) -> u32 {
    u32::try_from(値).unwrap_or_else(|_| panic!("数がu32に収まらない(拘束グラフの生成が保証する不変条件の破れ): {値}"))
}
