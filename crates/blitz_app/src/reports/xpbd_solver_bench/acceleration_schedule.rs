//! 計測の刻みごとの加速度の予定。重力は全刻みに掛かり、外力(横向きの加速度)は先頭の数刻みだけ掛ける。
//! 拘束が破れる初期条件を作るための外力であり、全拘束が静止長に一致したままでは何も測れない。
//! CPUの参照計算とGPUの定数が同じ値を読むよう、加速度による変位はこの1箇所で刻み幅の2乗を掛けて導く。

use blitz_math::{メートル毎秒毎秒, 秒};
use blitz_render::xpbd_solver_bench_probe::XPBD計測の刻みの定数;
use blitz_sim::constraint_graph::一様な加速度;
use blitz_sim::刻み幅;

use crate::error::起動エラー;

const 刻み幅の秒: f32 = 1.0 / 60.0;
const 重力の加速度: f32 = -9.8;
const 外力の加速度: f32 = 20.0;
const 外力を掛ける刻み数: u32 = 30;

pub(super) fn 刻み幅() -> Result<刻み幅, 起動エラー> {
    Ok(刻み幅::生成する(秒::生成する(刻み幅の秒))?)
}

/// その刻みに全点へ掛かる加速度。
pub(super) fn 刻みの加速度(刻み: u32) -> 一様な加速度 {
    let 零 = メートル毎秒毎秒::生成する(0.0);
    let 重力 = 一様な加速度::成分から生成する(零, メートル毎秒毎秒::生成する(重力の加速度), 零);
    if 刻み < 外力を掛ける刻み数 {
        重力 + 一様な加速度::成分から生成する(メートル毎秒毎秒::生成する(外力の加速度), 零, 零)
    } else {
        重力
    }
}

/// GPUの定数へ書く刻みごとの値。加速度による変位は参照計算の`一刻みの変位`と同じ演算で導く。
pub(super) fn 刻みの定数一覧(刻み数: u32, 刻み幅: 刻み幅) -> Vec<XPBD計測の刻みの定数> {
    let 秒 = 刻み幅.秒().値();
    (0..刻み数)
        .map(|刻み| {
            let 変位 = 刻みの加速度(刻み).一刻みの変位(刻み幅);
            XPBD計測の刻みの定数 {
                加速度による変位: [変位.x().値(), 変位.y().値(), 変位.z().値()],
                刻み幅の2乗の逆数: 1.0 / (秒 * 秒),
            }
        })
        .collect()
}
