//! 計測の報告の行の綴り。鍵は`鍵=値`の形で並べ、xtaskの計測(`xtask/src/xpbd_solver_bench/parse.rs`)が同じ綴りで読む。
//! 綴りの契約は`cargo xtask conform`の台帳(`xtask/src/conform/wording_contract/table/xpbd_solver_bench.rs`)が守る。

use blitz_render::xpbd_solver_bench_probe::XPBD並列方式;
use blitz_render::xpbd_solver_bench_probe::XPBD計測の読み戻し;
use blitz_sim::constraint_graph::拘束グラフの参照計算;

use super::comparison::突き合わせの結果;
use super::fixture::計測の題材;
use crate::cli::{XPBD並列方式計測の指定, XPBD計測のグラフの種別};

pub(super) fn 題材を出す(指定: &XPBD並列方式計測の指定, 題材: &計測の題材) {
    println!(
        "XPBD並列方式計測 方式={} グラフ={} 点の数={} 拘束の数={} 反復回数={} 刻み数={} 色の数={} グラフ生成ミリ秒={:.3} 前計算ミリ秒={:.3}",
        方式の語(指定.方式),
        グラフの語(指定.グラフ),
        題材.グラフ.点の数(),
        題材.グラフ.拘束の数(),
        指定.反復回数,
        指定.刻み数,
        題材.色の区間一覧.len(),
        題材.生成ミリ秒,
        題材.前計算ミリ秒
    );
}

/// 状況は全実行で同じ機材の同じ層であるため先頭の実行の値を出し、件数は全実行の合計を出す。
pub(super) fn 検証を出す(読み戻し一覧: &[&XPBD計測の読み戻し]) {
    let 状況 = 読み戻し一覧.first().map_or("環境に無い", |読み戻し| 読み戻し.検証層の状況.呼び名());
    let 件数: u64 = 読み戻し一覧.iter().map(|読み戻し| 読み戻し.検証件数).sum();
    println!("XPBD検証 状況={状況} 件数={件数}");
}

pub(super) fn 再現性を出す(突き合わせ: &突き合わせの結果) {
    println!(
        "XPBD再現性 位置={} 乗数={} 位置の指紋={} 乗数の指紋={}",
        一致の語(突き合わせ.位置が一致するか),
        一致の語(突き合わせ.乗数が一致するか),
        突き合わせ.位置の指紋,
        突き合わせ.乗数の指紋
    );
}

/// 長い実行の収束。GPUとCPUの拘束違反の二乗平均平方根を並べ、位置の差は出さない(軌道が離れるため意味を持たない)。
pub(super) fn 収束を出す(突き合わせ: &突き合わせの結果, 参照: &拘束グラフの参照計算) {
    println!(
        "XPBD収束 GPUの拘束違反の二乗平均平方根={:.6e} CPUの拘束違反の二乗平均平方根={:.6e} 全て有限={}",
        突き合わせ.gpuの拘束違反の二乗平均平方根,
        参照.拘束違反の二乗平均平方根(),
        if 突き合わせ.全て有限か { "はい" } else { "いいえ" }
    );
}

/// 短い実行でのCPUの参照計算との差。
pub(super) fn 参照との差を出す(比較の刻み数: u32, 突き合わせ: &突き合わせの結果) {
    println!(
        "XPBDのCPU参照との差 比較の刻み数={比較の刻み数} 位置の最大差={:.6e} 位置の平均差={:.6e} 乗数の最大差={:.6e} 乗数の平均差={:.6e}",
        突き合わせ.位置の最大差, 突き合わせ.位置の平均差, 突き合わせ.乗数の最大差, 突き合わせ.乗数の平均差
    );
}

pub(super) fn 資源を出す(方式: XPBD並列方式, 読み戻し: &XPBD計測の読み戻し) {
    println!(
        "XPBD資源 バッファ合計バイト数={} 一刻みのディスパッチ数={} 原子演算={}",
        読み戻し.バッファの合計バイト数,
        読み戻し.一刻みのディスパッチ数,
        if 方式 == XPBD並列方式::原子加算 { "あり" } else { "なし" }
    );
}

fn 方式の語(方式: XPBD並列方式) -> &'static str {
    match 方式 {
        XPBD並列方式::原子加算 => "atomic",
        XPBD並列方式::グラフ彩色 => "coloring",
        XPBD並列方式::二段階 => "two-stage",
    }
}

fn グラフの語(グラフ: XPBD計測のグラフの種別) -> &'static str {
    match グラフ {
        XPBD計測のグラフの種別::規則格子 => "grid",
        XPBD計測のグラフの種別::不規則 => "irregular",
    }
}

fn 一致の語(一致するか: bool) -> &'static str {
    if 一致するか { "一致" } else { "不一致" }
}
