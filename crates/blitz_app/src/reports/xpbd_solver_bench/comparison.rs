//! 読み戻しの突き合わせ: 2回の実行のビット一致と指紋、GPUの位置での拘束違反、CPUの参照計算との差の最大値と平均。
//! 判定はしない(許容差との比較はxtaskが持つ)。非有限値はそのまま最大差へ現れる(比較の前に落とさない)。

use blitz_math::{メートル, ワールド, 位置};
use blitz_render::xpbd_solver_bench_probe::XPBD計測の読み戻し;
use blitz_sim::constraint_graph::{拘束グラフの参照計算, 拘束違反の二乗平均平方根};

use super::fixture::計測の題材;
use super::sha256;

pub(super) struct 突き合わせの結果 {
    pub(super) 位置が一致するか: bool,
    pub(super) 乗数が一致するか: bool,
    pub(super) 位置の指紋: String,
    pub(super) 乗数の指紋: String,
    pub(super) gpuの拘束違反の二乗平均平方根: f64,
    pub(super) 位置の最大差: f64,
    pub(super) 位置の平均差: f64,
    pub(super) 乗数の最大差: f64,
    pub(super) 乗数の平均差: f64,
    pub(super) 全て有限か: bool,
}

pub(super) fn 突き合わせる(
    題材: &計測の題材,
    一回目: &XPBD計測の読み戻し,
    二回目: &XPBD計測の読み戻し,
    参照: &拘束グラフの参照計算,
) -> 突き合わせの結果 {
    let 一回目の位置のバイト列 = 位置のバイト列(&一回目.位置);
    let 一回目の乗数のバイト列 = 乗数のバイト列(&一回目.ラグランジュ乗数);
    let gpuの位置: Vec<位置<ワールド>> = 一回目.位置.iter().map(|成分| 読み戻した成分から位置を組む(*成分)).collect();
    let (位置の最大差, 位置の平均差) = 差の最大と平均(
        gpuの位置
            .iter()
            .zip(参照.位置一覧())
            .map(|(gpu, cpu)| f64::from((*gpu - *cpu).長さ().値())),
    );
    let (乗数の最大差, 乗数の平均差) = 差の最大と平均(
        一回目
            .ラグランジュ乗数
            .iter()
            .zip(参照.ラグランジュ乗数一覧())
            .map(|(gpu, cpu)| f64::from((gpu - cpu.値()).abs())),
    );
    突き合わせの結果 {
        位置が一致するか: 一回目の位置のバイト列 == 位置のバイト列(&二回目.位置),
        乗数が一致するか: 一回目の乗数のバイト列 == 乗数のバイト列(&二回目.ラグランジュ乗数),
        位置の指紋: sha256::十六進の指紋を計算する(&一回目の位置のバイト列),
        乗数の指紋: sha256::十六進の指紋を計算する(&一回目の乗数のバイト列),
        gpuの拘束違反の二乗平均平方根: 拘束違反の二乗平均平方根(題材.グラフ.拘束一覧(), &gpuの位置),
        位置の最大差,
        位置の平均差,
        乗数の最大差,
        乗数の平均差,
        全て有限か: 一回目.位置.iter().all(|成分| 成分.iter().all(|値| 値.is_finite()))
            && 一回目.ラグランジュ乗数.iter().all(|値| 値.is_finite()),
    }
}

fn 読み戻した成分から位置を組む(成分: [f32; 4]) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(成分[0]), メートル::生成する(成分[1]), メートル::生成する(成分[2]))
}

/// 非有限値は最大値の比較で必ず勝つように扱う(比較で落ちて見えなくなることを避ける)。
fn 差の最大と平均(差一覧: impl Iterator<Item = f64>) -> (f64, f64) {
    let mut 最大 = 0.0f64;
    let mut 合計 = 0.0f64;
    let mut 件数 = 0u32;
    for 差 in 差一覧 {
        最大 = if 差.is_nan() || 差 > 最大 { 差 } else { 最大 };
        合計 += 差;
        件数 += 1;
    }
    (最大, if 件数 == 0 { 0.0 } else { 合計 / f64::from(件数) })
}

fn 位置のバイト列(位置一覧: &[[f32; 4]]) -> Vec<u8> {
    位置一覧
        .iter()
        .flat_map(|成分| 成分[..3].iter().flat_map(|値| 値.to_le_bytes()))
        .collect()
}

fn 乗数のバイト列(乗数一覧: &[f32]) -> Vec<u8> {
    乗数一覧.iter().flat_map(|値| 値.to_le_bytes()).collect()
}
