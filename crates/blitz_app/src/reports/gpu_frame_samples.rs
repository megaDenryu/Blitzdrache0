//! パス別GPU時間の窓へ入る前の生の値のコンソール出力。担当するのは行の綴りと、値をどの桁で書くかである。
//!
//! 分位と同じ4桁で書くのは、報告の分位が補間しない最近傍順位法で選んだ実在の標本そのものだからである。
//! 4桁への丸めは単調であるため、丸めた列を並べ替えた順位の値は、元の列の同じ順位の値を丸めたものと必ず一致する。
//! この性質があるため、読み手はこの列から分位を計算し直して報告値と厳密に突き合わせられる
//! (`xtask/src/depth_prepass_cost/quantile_check.rs`がその突き合わせを行う)。
//!
//! 見出しに窓の標本数を書くのは、読み手が「直近の何フレームから採った分位か」をもう1つの台帳として持たないためである。

use blitz_render::gpu_pass_timing::{フレーム別の標本, 窓の標本数};

pub(crate) fn 表示する(標本一覧: &[フレーム別の標本]) {
    if 標本一覧.is_empty() {
        println!("パス別GPU時間のフレーム別生値: 記録できなかった(タイムスタンプ非対応、または1フレームも計測が完了していない)");
        return;
    }
    println!(
        "パス別GPU時間のフレーム別生値 窓の標本数={窓の標本数} 分位=最近傍順位法 件数={}",
        標本一覧.len()
    );
    for 標本 in 標本一覧 {
        println!("  生値\t{}\t{}\t{:.4}", 標本.読み取り順(), 標本.区間名(), 標本.経過ミリ秒());
    }
}
