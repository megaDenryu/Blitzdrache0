//! 遠方環境の焼き直し判定の記録の報告。受け取るのは記録、返す代わりに機械可読な1行を標準出力へ出す。
//!
//! 鍵をそのまま出すのは、太陽円盤の明るさだけを変えた対でこの行が1文字も変わらないことを検収が要求するためである
//! (`cargo xtask sky-time`の円盤A/B)。鍵は遠方環境の焼き上げの即時定数をすべて含むため、鍵が対で同じことは
//! 焼いた立方体画像が対で同じことを意味する。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Ic-3bの実装」

use crate::app::{太陽天頂区間の記録, 遠方環境の鍵の記録};

pub(crate) fn 遠方環境の鍵を表示する(記録: &遠方環境の鍵の記録) {
    println!(
        "遠方環境の鍵 判定したフレーム数={} 焼き直すと判断したフレーム数={} 直近の鍵={}",
        記録.判定したフレーム数(),
        記録.焼き直すと判断したフレーム数(),
        記録.直近の鍵の表記()
    );
}

/// 太陽天頂区間の記録の報告。区間の変化回数を整数で出すのは、焼き直したフレーム数が「変化回数+初回の1回」に
/// 一致することを検収が整数のまま確かめられるようにするためである。
/// 直近の区間識別を並べるのは、境界の取り違えを実行のあいだで突き合わせられるようにするためである。
pub(crate) fn 太陽天頂区間を表示する(記録: &太陽天頂区間の記録) {
    let 直近 = match 記録.直近の区間識別() {
        Some(識別) => 識別.to_string(),
        None => "なし".to_string(),
    };
    println!(
        "太陽天頂区間 判定したフレーム数={} 区間が変わった回数={} 直近の区間識別={直近}",
        記録.判定したフレーム数(),
        記録.区間が変わった回数()
    );
}
