//! ゲーム配線がカメラへ渡す面。担当するのは、カメラの系統の切替の操作を受け取ること、描画機会ごとにこの描画の表示距離を
//! 決めること、開発用UIへ渡す移動とカメラの計器を作ることである。遊ばない起動ではどれもカメラに触れない。
//!
//! 世界の形を尋ねる口をここで組むのは、口が高さ場の読み口(ゲーム配線が持つ)とストリーミング調停(アプリが持つ)の両方を
//! 借りるためである。フレームの工程は調停の出どころだけを渡し、口の組み方を知らない。

use blitz_math::メートル;

use super::camera_wiring::この描画のカメラの入力;
use super::instrument::移動とカメラの計器;
use super::world_shape_port::{
    エンジンの問い合わせを包んだ世界の形を尋ねる口, 世界の形を尋ねる口の実装エラー, 読込済みチャンクの形の出どころ
};
use super::ゲーム配線;

/// この描画のエンジンのカメラへの指示。遊ばない起動ではカメラを触らない。
pub(crate) enum 表示距離の指示 {
    カメラを触らない,
    据える(メートル),
}

impl ゲーム配線 {
    /// 操作入力を確定した直後に1描画に1度だけ呼ぶ。押した瞬間の操作であり、刻みへは配らない。
    pub(super) fn カメラの系統の切替の操作を受け取る(&mut self, 押した瞬間か: bool) {
        match self {
            Self::ゲームを遊ばない => {}
            Self::キツネの場所巡り(配線) => 配線.カメラを借りる().切替の操作を受け取る(押した瞬間か),
            Self::歩くだけ(配線) => 配線.カメラを借りる().切替の操作を受け取る(押した瞬間か),
        }
    }

    /// この描画の表示距離を決める。問い合わせの失敗は型付きエラーで上へ返し、黙って理想距離へ落とさない。
    pub(crate) fn この描画の表示距離を決める(
        &mut self,
        出どころ: 読込済みチャンクの形の出どころ<'_>,
        入力: この描画のカメラの入力,
    ) -> Result<表示距離の指示, 世界の形を尋ねる口の実装エラー> {
        let (カメラ, 高さ場の読み口) = match self {
            Self::ゲームを遊ばない => return Ok(表示距離の指示::カメラを触らない),
            Self::キツネの場所巡り(配線) => 配線.カメラと高さ場の読み口を借りる(),
            Self::歩くだけ(配線) => 配線.カメラと高さ場の読み口を借りる(),
        };
        let mut 口 = エンジンの問い合わせを包んだ世界の形を尋ねる口::組む(高さ場の読み口, 出どころ)?;
        Ok(表示距離の指示::据える(カメラ.この描画の表示距離を決める(&mut 口, 入力)?))
    }

    /// 開発用UIへ渡す計器。遊ばない起動では`None`であり、開発用UIは計器の面を描かない。
    pub(crate) fn 移動とカメラの計器を作る(&self) -> Option<移動とカメラの計器> {
        match self {
            Self::ゲームを遊ばない => None,
            Self::キツネの場所巡り(配線) => Some(移動とカメラの計器 {
                移動: 配線.移動の計器を作る(),
                カメラ: 配線.カメラ().計器を作る(),
            }),
            Self::歩くだけ(配線) => Some(移動とカメラの計器 {
                移動: 配線.移動の計器を作る(),
                カメラ: 配線.カメラ().計器を作る(),
            }),
        }
    }
}
