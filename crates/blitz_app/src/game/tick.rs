//! ゲーム配線の固定刻み1本ぶんの更新。呼ばれるのは刻みを回す工程(`app/frame/game_steps.rs`)からであり、
//! 描画機会ごとの操作の確定やカメラの供給とは呼び出しの頻度が違う。触れるのは遊ぶゲームの枝の配線だけである。
//!
//! 読込済みチャンクの形の出どころを刻みごとに受け取るのは、世界の形を尋ねる口がその描画のストリーミング調停の借用に
//! 縛られ、配線が持ち越せないためである。問い合わせの失敗は型付きエラーで上へ返し、黙って動かない刻みにしない。

use std::time::Duration;

use blitz_game::{前へ進む向きの方位角, 確定済みの操作入力};
use blitz_math::{ラジアン, 秒};

use super::world_shape_port::{世界の形を尋ねる口の実装エラー, 読込済みチャンクの形の出どころ};
use super::{ゲームの終了要求, ゲーム配線};

impl ゲーム配線 {
    /// ゲーム更新を1刻みだけ行う。刻みの長さを受け取るのは、時間の進め方をこの配線が持たないためである。
    /// カメラのヨーを受け取るのは、移動をカメラの向き基準にするためである。ヨーをゲームの前へ進む向きへ写すのはこの配線であり、
    /// ゲームロジック層はカメラの型を1つも知らない。
    pub(crate) fn 一刻み進める(
        &mut self,
        出どころ: 読込済みチャンクの形の出どころ<'_>,
        操作入力: 確定済みの操作入力,
        カメラのヨー: ラジアン,
        一刻みの秒: 秒,
    ) -> Result<ゲームの終了要求, 世界の形を尋ねる口の実装エラー> {
        let 前へ進む向き = 前へ進む向きの方位角::生成する(カメラのヨー);
        match self {
            Self::ゲームを遊ばない => {}
            Self::キツネの場所巡り(配線) => {
                配線.一刻み進める(出どころ, 操作入力, 前へ進む向き, 一刻みの秒)?;
                if 配線.終了が決まったか() {
                    return Ok(ゲームの終了要求::終了する);
                }
            }
            Self::歩くだけ(配線) => 配線.一刻み進める(出どころ, 操作入力, 前へ進む向き, 一刻みの秒)?,
        }
        Ok(ゲームの終了要求::続ける)
    }

    /// 刻みを回す工程が測った1刻みの所要時間を記録へ渡す。時計を読むのは工程であり、配線は足すだけである。
    pub(crate) fn 刻みの所要時間を記録する(&mut self, 所要時間: Duration) {
        match self {
            Self::ゲームを遊ばない => {}
            Self::キツネの場所巡り(配線) => 配線.移動の記録を借りる().刻みの所要時間を記録する(所要時間),
            Self::歩くだけ(配線) => 配線.移動の記録を借りる().刻みの所要時間を記録する(所要時間),
        }
    }
}
