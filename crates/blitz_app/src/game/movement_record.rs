//! 移動の観測の記録: 刻みごとに胴体の移動が返す観測を受け取り、計器と終了時の報告が読む累計と分布を持つ。
//! キツネの場所巡りと歩くだけのゲームの両方がこの1つを持つ(判断14)。
//!
//! 刻みの所要時間を受け取るのは、実時間を読む場所をフレームの工程へ閉じるためである。ここは渡された長さを分布へ足すだけであり、
//! 時計を1度も読まない。所要時間はゲームの状態へ1つも影響せず、報告と計器の材料にしかならない。
//! 所要時間は全刻みの分布と、その刻みの問い合わせ件数ごとの分布の両方へ足す。件数はその刻みの観測から読む。
//! 注意: 刻みの観測を記録した後にその刻みの所要時間を記録する順序が不変条件である(配線の`一刻み進める`が観測を記録してから
//! 刻みを回す工程が所要時間を渡す)。観測の無い刻みへ所要時間が届いたら配線のバグであり、到達したら止める。
//! 刻みが見た世界の形の版もここが持つ。版を進めるのはストリーミング調停であり、ここは刻みが受け取った値を`shape_version_record`へ渡すだけである。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断13」「性能予算」

use std::time::Duration;

use blitz_game::{移動の観測, 移動状態};

use super::instrument::{直前の刻みの移動, 移動の計器};
use super::query_count_distribution::{問い合わせ件数の分布, 問い合わせ件数の要約};
use super::shape_version_record::{刻みが見た世界の形の版の要約, 刻みが見た世界の形の版の記録};
use super::step_time_by_query_count::{件数別の刻みの所要時間の要約, 問い合わせ件数別の刻みの所要時間の分布};
use super::step_time_distribution::{刻みの所要時間の分布, 刻みの所要時間の要約};

/// 終了時の報告へ渡す、移動の観測の記録の要約。4つは同じ記録から同時に作られ、別々に運ぶと要約の出どころが揃わない。
pub(crate) struct 移動の観測の要約 {
    pub(crate) 問い合わせ件数: 問い合わせ件数の要約,                                // 全刻みで世界の形を尋ねた問いの数の分布。1刻みあたりの件数を性能予算と突き合わせる材料
    pub(crate) 刻みの所要時間: 刻みの所要時間の要約,                                // 刻みを回す工程が測ったゲーム更新のCPU時間の分布
    pub(crate) 問い合わせ件数別の刻みの所要時間: Vec<件数別の刻みの所要時間の要約>, // 件数の昇順。1件あたりの費用を件数別のp50の差として読む材料
    pub(crate) 刻みが見た世界の形の版: 刻みが見た世界の形の版の要約,                // 刻みが見た読込済みチャンクの形の版が、刻みのあいだで変わった回数
}

pub(super) struct 移動の観測の記録 {
    直前の刻み: 直前の刻みの移動,
    評価が終わらずに動かなかった刻みの数: u32,
    問い合わせ件数: 問い合わせ件数の分布,
    刻みの所要時間: 刻みの所要時間の分布,
    問い合わせ件数別の刻みの所要時間: 問い合わせ件数別の刻みの所要時間の分布,
    刻みが見た世界の形の版: 刻みが見た世界の形の版の記録,
}

impl 移動の観測の記録 {
    pub(super) fn まだ刻んでいない記録を作る() -> Self {
        Self {
            直前の刻み: 直前の刻みの移動::まだ刻んでいない,
            評価が終わらずに動かなかった刻みの数: 0,
            問い合わせ件数: 問い合わせ件数の分布::まだ刻んでいない分布を作る(),
            刻みの所要時間: 刻みの所要時間の分布::まだ刻んでいない分布を作る(),
            問い合わせ件数別の刻みの所要時間: 問い合わせ件数別の刻みの所要時間の分布::まだ刻んでいない分布を作る(),
            刻みが見た世界の形の版: 刻みが見た世界の形の版の記録::まだ刻んでいない記録を作る(),
        }
    }

    pub(super) fn 刻みの観測を記録する(&mut self, 観測: 移動の観測) {
        if 観測.完全性で動かなかったか {
            self.評価が終わらずに動かなかった刻みの数 = self.評価が終わらずに動かなかった刻みの数.saturating_add(1);
        }
        self.問い合わせ件数.記録する(観測.問い合わせ件数);
        self.直前の刻み = 直前の刻みの移動::刻んだ { 観測 };
    }

    pub(super) fn 刻みの所要時間を記録する(&mut self, 所要時間: Duration) {
        self.刻みの所要時間.記録する(所要時間);
        let 直前の刻みの移動::刻んだ { 観測 } = self.直前の刻み else {
            panic!("刻みの所要時間が観測の無い刻みへ届いた(観測を記録してから所要時間を記録する不変条件が破れている)");
        };
        self.問い合わせ件数別の刻みの所要時間.記録する(観測.問い合わせ件数, 所要時間);
    }

    pub(super) fn 刻みが見た世界の形の版を記録する(&mut self, 版: blitz_engine::読込済みチャンクの形の版) {
        self.刻みが見た世界の形の版.刻みが見た版を記録する(版);
    }

    pub(super) fn 計器を作る(&self, 移動状態: 移動状態) -> 移動の計器 {
        移動の計器 {
            移動状態,
            直前の刻み: self.直前の刻み,
            評価が終わらずに動かなかった刻みの数: self.評価が終わらずに動かなかった刻みの数,
        }
    }

    pub(super) fn 要約する(&self) -> 移動の観測の要約 {
        移動の観測の要約 {
            問い合わせ件数: self.問い合わせ件数.要約する(),
            刻みの所要時間: self.刻みの所要時間.要約する(),
            問い合わせ件数別の刻みの所要時間: self.問い合わせ件数別の刻みの所要時間.件数の昇順に要約する(),
            刻みが見た世界の形の版: self.刻みが見た世界の形の版.要約する(),
        }
    }
}
