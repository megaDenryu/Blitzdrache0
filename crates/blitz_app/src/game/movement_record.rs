//! 移動の観測の記録: 刻みごとに胴体の移動が返す観測を受け取り、計器と終了時の報告が読む累計を持つ。
//! キツネの場所巡りと歩くだけのゲームの両方がこの1つを持つ(判断14)。
//!
//! 刻みの所要時間を受け取るのは、実時間を読む場所をフレームの工程へ閉じるためである。ここは渡された長さを足すだけであり、
//! 時計を1度も読まない。所要時間はゲームの状態へ1つも影響せず、報告と計器の材料にしかならない。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断13」「性能予算」

use std::time::Duration;

use blitz_game::{移動の観測, 移動状態};

use super::instrument::{直前の刻みの移動, 移動の計器};

pub(super) struct 移動の観測の記録 {
    直前の刻み: 直前の刻みの移動,
    完全性で動かなかった刻みの数: u32,
    問い合わせ件数の合計: u64,
    刻みの回数: u32,
    刻みの所要時間の合計: Duration,
}

impl 移動の観測の記録 {
    pub(super) fn まだ刻んでいない記録を作る() -> Self {
        Self {
            直前の刻み: 直前の刻みの移動::まだ刻んでいない,
            完全性で動かなかった刻みの数: 0,
            問い合わせ件数の合計: 0,
            刻みの回数: 0,
            刻みの所要時間の合計: Duration::ZERO,
        }
    }

    pub(super) fn 刻みの観測を記録する(&mut self, 観測: 移動の観測) {
        if 観測.完全性で動かなかったか {
            self.完全性で動かなかった刻みの数 = self.完全性で動かなかった刻みの数.saturating_add(1);
        }
        self.問い合わせ件数の合計 = self.問い合わせ件数の合計.saturating_add(u64::from(観測.問い合わせ件数.値()));
        self.直前の刻み = 直前の刻みの移動::刻んだ { 観測 };
    }

    pub(super) fn 刻みの所要時間を記録する(&mut self, 所要時間: Duration) {
        self.刻みの回数 = self.刻みの回数.saturating_add(1);
        self.刻みの所要時間の合計 = self.刻みの所要時間の合計.saturating_add(所要時間);
    }

    pub(super) fn 計器を作る(&self, 移動状態: 移動状態) -> 移動の計器 {
        移動の計器 {
            移動状態,
            直前の刻み: self.直前の刻み,
            完全性で動かなかった刻みの数: self.完全性で動かなかった刻みの数,
        }
    }

    pub(super) fn 問い合わせ件数の合計(&self) -> u64 {
        self.問い合わせ件数の合計
    }

    pub(super) fn 刻みの回数(&self) -> u32 {
        self.刻みの回数
    }

    pub(super) fn 刻みの所要時間の合計(&self) -> Duration {
        self.刻みの所要時間の合計
    }
}
