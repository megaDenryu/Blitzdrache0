//! 終了時の報告へ渡すゲームの進行の要約を所有する。値だけを運ぶ器であり、表示の仕方は`reports/game.rs`が決める。

use std::time::Duration;

/// そのプロセスがゲームをどこまで回したかの要約。
pub(crate) struct ゲーム進行の要約 {
    pub(crate) ゲームの表示名: &'static str,
    pub(crate) ゲーム更新の回数: u32, // 1刻みは描画フレーム1回ぶんであるため、ゲームを回した描画フレーム数と一致する
    pub(crate) 最後の進行段階の呼び名: &'static str,
    pub(crate) 到達済みの目的地数: usize,
    pub(crate) 目的地の総数: usize,
    pub(crate) プレイヤーの大域位置: blitz_math::大域ワールド位置, // 最後のゲーム更新の後の位置。動く個体が実際に動いたかを、絵を見ずに実行の結果で確かめるために出す
    pub(crate) 最後の移動状態の呼び名: &'static str, // 最後のゲーム更新の後に接地中か空中か。着地していることを絵を見ずに確かめるために出す
    pub(crate) 移動の問い合わせ件数の合計: u64,      // 全刻みで世界の形を尋ねた問いの数。1刻みあたりの件数を性能予算と突き合わせる材料
    pub(crate) 所要時間を測った刻みの回数: u32,
    pub(crate) 刻みの所要時間の合計: Duration, // 刻みを回す工程が測ったゲーム更新のCPU時間の合計
}
