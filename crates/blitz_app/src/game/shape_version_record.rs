//! 刻みが見た世界の形の版の記録: 刻みごとに受け取った読込済みチャンクの形の版を覚え、直前の刻みと違う版を見た回数を数える器。
//! 1つの描画の全刻みが同じ形を見たこと(描画の中で回数が増えないこと)と、描画をまたいで形が変わった回数を、
//! 終了時の報告が読む。版そのものはストリーミング調停が進め、ここは受け取った値を比べるだけである。

use blitz_engine::読込済みチャンクの形の版;

pub(super) struct 刻みが見た世界の形の版の記録 {
    直前の刻み: 直前の刻みが見た版,
    刻んだ回数: u32,
    版の変わった回数: u32,
}

// 直前の刻みが見た版。まだ1度も刻んでいない状態を番兵の値でなく選択肢で持つ。
#[derive(Debug, Clone, Copy)]
enum 直前の刻みが見た版 {
    まだ刻んでいない,
    刻んだ(読込済みチャンクの形の版),
}

/// 終了時の報告へ渡す要約。1度も刻んでいない状態をそのまま選択肢で持つ。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 刻みが見た世界の形の版の要約 {
    まだ刻んでいない,
    刻んだ {
        刻んだ回数: u32,
        版の変わった回数: u32,
        最後に見た版: 読込済みチャンクの形の版,
    },
}

impl 刻みが見た世界の形の版の記録 {
    pub(super) fn まだ刻んでいない記録を作る() -> Self {
        Self {
            直前の刻み: 直前の刻みが見た版::まだ刻んでいない,
            刻んだ回数: 0,
            版の変わった回数: 0,
        }
    }

    /// 最初の刻みは比べる相手が無いため、変わった回数に数えない。
    pub(super) fn 刻みが見た版を記録する(&mut self, 版: 読込済みチャンクの形の版) {
        if let 直前の刻みが見た版::刻んだ(前の版) = self.直前の刻み
            && 前の版 != 版
        {
            self.版の変わった回数 = self.版の変わった回数.saturating_add(1);
        }
        self.刻んだ回数 = self.刻んだ回数.saturating_add(1);
        self.直前の刻み = 直前の刻みが見た版::刻んだ(版);
    }

    pub(super) fn 要約する(&self) -> 刻みが見た世界の形の版の要約 {
        match self.直前の刻み {
            直前の刻みが見た版::まだ刻んでいない => 刻みが見た世界の形の版の要約::まだ刻んでいない,
            直前の刻みが見た版::刻んだ(版) => 刻みが見た世界の形の版の要約::刻んだ {
                刻んだ回数: self.刻んだ回数,
                版の変わった回数: self.版の変わった回数,
                最後に見た版: 版,
            },
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn 版(進める回数: u32) -> 読込済みチャンクの形の版 {
        (0..進める回数).fold(読込済みチャンクの形の版::最初を作る(), |版, _| 版.次を作る())
    }

    #[test]
    fn 一つの描画の全刻みが同じ版を見ると変わった回数は増えない() {
        let mut 記録 = 刻みが見た世界の形の版の記録::まだ刻んでいない記録を作る();
        for _ in 0..4 {
            記録.刻みが見た版を記録する(版(3));
        }
        assert_eq!(
            記録.要約する(),
            刻みが見た世界の形の版の要約::刻んだ {
                刻んだ回数: 4,
                版の変わった回数: 0,
                最後に見た版: 版(3)
            }
        );
    }

    #[test]
    fn 刻みを一本も進めない描画で版が進んでも次の描画の刻みが新しい版を見る() {
        let mut 記録 = 刻みが見た世界の形の版の記録::まだ刻んでいない記録を作る();
        記録.刻みが見た版を記録する(版(0));
        // 刻み0本の描画が2回続き、そのあいだに形が2度変わった。記録には何も届かない。
        記録.刻みが見た版を記録する(版(2));
        assert_eq!(
            記録.要約する(),
            刻みが見た世界の形の版の要約::刻んだ {
                刻んだ回数: 2,
                版の変わった回数: 1,
                最後に見た版: 版(2)
            }
        );
    }

    #[test]
    fn まだ刻んでいない記録の要約はその選択肢になる() {
        let 記録 = 刻みが見た世界の形の版の記録::まだ刻んでいない記録を作る();
        assert_eq!(記録.要約する(), 刻みが見た世界の形の版の要約::まだ刻んでいない);
    }
}
