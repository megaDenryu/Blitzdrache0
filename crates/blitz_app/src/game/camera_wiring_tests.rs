//! プレイヤーカメラの配線の検査。切替の操作が方針に従うこと、デバッグ用の系統が遮蔽を見ないこと、
//! プレイヤー用の系統が規則の答えを表示距離にすることを見る。世界の形を尋ねる口は常に半分で触れる検査用の口で代える。

use blitz_game::{
    世界の形を尋ねる口, 動けた割合, 掃引が最初に触れる面, 掃引の完全性, 掃引の接触, 掃引の答え, 胴体カプセル
};
use blitz_math::{メートル, ワールド, 変位, 大域メートル, 大域ワールド位置, 方向, 秒};

use super::camera_system::カメラの系統;
use super::camera_wiring::{この描画のカメラの入力, プレイヤーカメラの配線};
use crate::cli::起動モード;
use crate::input::ゲーム操作の適用方針;

/// どの掃引にも変位の半分で触れたと答える口。
struct 常に半分で触れる口;

impl 世界の形を尋ねる口 for 常に半分で触れる口 {
    type 問い合わせエラー = std::convert::Infallible;

    fn 掃引した胴体が最初に触れる面を求める(
        &mut self,
        胴体: 胴体カプセル,
        掃引の変位: 変位<ワールド>,
    ) -> Result<掃引の答え, Self::問い合わせエラー> {
        self.掃引した球が最初に触れる面を求める(胴体.足元の位置(), 胴体.半径(), 掃引の変位)
    }

    fn 掃引した球が最初に触れる面を求める(
        &mut self,
        中心: 大域ワールド位置,
        _半径: メートル,
        _掃引の変位: 変位<ワールド>,
    ) -> Result<掃引の答え, Self::問い合わせエラー> {
        let 法線 = 方向::生成する(0.0, 0.0, -1.0).unwrap_or_else(|誤り| panic!("検査の法線を作れない: {誤り}"));
        let 割合 = 動けた割合::生成する(0.5).unwrap_or_else(|誤り| panic!("検査の割合を作れない: {誤り}"));
        Ok(掃引の答え::生成する(
            掃引が最初に触れる面::触れる(掃引の接触::生成する(割合, 中心, 法線)),
            掃引の完全性::対象範囲を完全に評価できた,
        ))
    }
}

fn 理想距離8メートルの入力() -> この描画のカメラの入力 {
    この描画のカメラの入力 {
        注視点: 大域ワールド位置::原点(),
        理想視点: 大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(0.0), 大域メートル::生成する(8.0)),
        理想距離: メートル::生成する(8.0),
        表示距離の下限: メートル::生成する(0.5),
        進めた時間: 秒::生成する(1.0 / 60.0),
    }
}

fn 系統を読む(配線: &プレイヤーカメラの配線) -> カメラの系統 {
    配線.計器を作る().系統
}

#[test]
fn 無期限実行では切替の操作で系統が交互に変わる() {
    let mut 配線 =
        プレイヤーカメラの配線::プレイヤー用で生成する(ゲーム操作の適用方針::起動モードから決める(起動モード::無期限実行));
    assert_eq!(系統を読む(&配線), カメラの系統::プレイヤー用);
    配線.切替の操作を受け取る(true);
    assert_eq!(系統を読む(&配線), カメラの系統::デバッグ用);
    配線.切替の操作を受け取る(false);
    assert_eq!(系統を読む(&配線), カメラの系統::デバッグ用);
    配線.切替の操作を受け取る(true);
    assert_eq!(系統を読む(&配線), カメラの系統::プレイヤー用);
}

/// 反証: フレーム数の決まった実行で切替が通ると、検収の絵が実行のたびに別の系統で撮られうる。
#[test]
fn フレーム数の決まった実行では切替の操作が系統を変えない() {
    let mut 配線 =
        プレイヤーカメラの配線::プレイヤー用で生成する(ゲーム操作の適用方針::起動モードから決める(起動モード::スモーク実行 {
            フレーム数: 3,
        }));
    配線.切替の操作を受け取る(true);
    assert_eq!(系統を読む(&配線), カメラの系統::プレイヤー用);
}

#[test]
fn プレイヤー用の系統は規則が決めた表示距離を答える() {
    let mut 配線 =
        プレイヤーカメラの配線::プレイヤー用で生成する(ゲーム操作の適用方針::起動モードから決める(起動モード::無期限実行));
    let 表示距離 = match 配線.この描画の表示距離を決める(&mut 常に半分で触れる口, 理想距離8メートルの入力()) {
        Ok(表示距離) => 表示距離,
        Err(誤り) => match 誤り {},
    };
    assert_eq!(表示距離, メートル::生成する(4.0));
}

