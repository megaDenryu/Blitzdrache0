//! プレイヤーカメラの配線の検査。切替の操作が方針に従うこと、デバッグ用の系統が遮蔽を見ないこと、
//! プレイヤー用の系統が規則の答えを表示距離にすること、デバッグ用の描画がプレイヤー用の復帰と保持の基準を上書きしないことを見る。
//! 世界の形を尋ねる口は `camera_wiring_test_ports` の検査用の口で代える。

use blitz_game::世界の形を尋ねる口;
use blitz_math::{メートル, 大域メートル, 大域ワールド位置, 秒};

use super::camera_system::カメラの系統;
use super::camera_wiring::{この描画のカメラの入力, プレイヤーカメラの配線};
use super::camera_wiring_test_ports::{常に半分で触れる口, 常に評価できない口};
use super::instrument::直前の描画のカメラ;
use crate::cli::起動モード;
use crate::input::ゲーム操作の適用方針;

fn 理想距離の入力(理想距離: f32) -> この描画のカメラの入力 {
    この描画のカメラの入力 {
        注視点: 大域ワールド位置::原点(),
        理想視点: 大域ワールド位置::生成する(
            大域メートル::生成する(0.0),
            大域メートル::生成する(0.0),
            大域メートル::生成する(f64::from(理想距離)),
        ),
        理想距離: メートル::生成する(理想距離),
        表示距離の下限: メートル::生成する(0.5),
        進めた時間: 秒::生成する(1.0 / 60.0),
    }
}

fn 無期限実行の配線() -> プレイヤーカメラの配線 {
    プレイヤーカメラの配線::プレイヤー用で生成する(ゲーム操作の適用方針::起動モードから決める(起動モード::無期限実行))
}

fn 系統を読む(配線: &プレイヤーカメラの配線) -> カメラの系統 {
    配線.計器を作る().系統
}

fn 描く<口: 世界の形を尋ねる口<問い合わせエラー = std::convert::Infallible>>(
    配線: &mut プレイヤーカメラの配線,
    口: &mut 口,
    理想距離: f32,
) -> メートル {
    match 配線.この描画の表示距離を決める(口, 理想距離の入力(理想距離)) {
        Ok(表示距離) => 表示距離,
        Err(誤り) => match 誤り {},
    }
}

#[test]
fn 無期限実行では切替の操作で系統が交互に変わる() {
    let mut 配線 = 無期限実行の配線();
    assert_eq!(系統を読む(&配線), カメラの系統::プレイヤー用);
    配線.切替の操作を受け取る(true);
    assert_eq!(系統を読む(&配線), カメラの系統::デバッグ用);
    配線.切替の操作を受け取る(false);
    assert_eq!(系統を読む(&配線), カメラの系統::デバッグ用);
    配線.切替の操作を受け取る(true);
    assert_eq!(系統を読む(&配線), カメラの系統::プレイヤー用);
}

/// 反証: フレーム数の決まった実行で切替が通ると、検収の絵が実行のたびに別の系統で撮られうる。
#[test]
fn フレーム数の決まった実行では切替の操作が系統を変えない() {
    let mut 配線 =
        プレイヤーカメラの配線::プレイヤー用で生成する(ゲーム操作の適用方針::起動モードから決める(起動モード::スモーク実行 {
            フレーム数: 3,
        }));
    配線.切替の操作を受け取る(true);
    assert_eq!(系統を読む(&配線), カメラの系統::プレイヤー用);
}

#[test]
fn プレイヤー用の系統は規則が決めた表示距離を答える() {
    let mut 配線 = 無期限実行の配線();
    assert_eq!(描く(&mut 配線, &mut 常に半分で触れる口, 8.0), メートル::生成する(4.0));
}

/// 反証: デバッグ用の系統でも遮蔽を避けると、めり込みを許す確認の構図が作れない。
#[test]
fn デバッグ用の系統は表示距離を理想距離のままにする() {
    let mut 配線 = 無期限実行の配線();
    配線.切替の操作を受け取る(true);
    assert_eq!(描く(&mut 配線, &mut 常に半分で触れる口, 8.0), メートル::生成する(8.0));
}

/// 反証: デバッグ用の描画で基準を理想距離へ上書きすると、戻した描画は8メートルを保ち、判断10の「未読込の中へ視点を出さない」を破る。
#[test]
fn デバッグ用を挟んで戻した評価できない描画はプレイヤー用が最後に決めた表示距離を保つ() {
    let mut 配線 = 無期限実行の配線();
    assert_eq!(描く(&mut 配線, &mut 常に半分で触れる口, 8.0), メートル::生成する(4.0));
    配線.切替の操作を受け取る(true);
    assert_eq!(描く(&mut 配線, &mut 常に半分で触れる口, 8.0), メートル::生成する(8.0));
    配線.切替の操作を受け取る(true);
    assert_eq!(描く(&mut 配線, &mut 常に評価できない口, 8.0), メートル::生成する(4.0));
}

/// 反証: デバッグ用の間に増えた理想距離を評価できない描画で足すと、確かめていない先へ視点を伸ばす。増えたぶんは掃引が完全な描画で初めて通る。
#[test]
fn デバッグ用の間に増えた理想距離は戻した評価できない描画では足されない() {
    let mut 配線 = 無期限実行の配線();
    assert_eq!(描く(&mut 配線, &mut 常に半分で触れる口, 8.0), メートル::生成する(4.0));
    配線.切替の操作を受け取る(true);
    assert_eq!(描く(&mut 配線, &mut 常に半分で触れる口, 9.0), メートル::生成する(9.0));
    配線.切替の操作を受け取る(true);
    assert_eq!(描く(&mut 配線, &mut 常に評価できない口, 9.0), メートル::生成する(4.0));
}

#[test]
fn デバッグ用の描画でも計器の直前の描画は更新される() {
    let mut 配線 = 無期限実行の配線();
    配線.切替の操作を受け取る(true);
    描く(&mut 配線, &mut 常に半分で触れる口, 8.0);
    assert!(matches!(配線.計器を作る().直前の描画, 直前の描画のカメラ::描いた { 表示距離, .. } if 表示距離 == メートル::生成する(8.0)));
}
