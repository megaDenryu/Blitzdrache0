//! プレイヤーカメラの配線: カメラの系統と、ゲームロジック層の「カメラの遮蔽と復帰」と、直前の描画で決めた値を1つに束ね、
//! 描画機会ごとに表示距離を決める。キツネの場所巡りと歩くだけのゲームの両方がこの1つを持つ(判断14)。
//!
//! 世界の形を尋ねる口を保持しないのは、口がその描画のストリーミング調停の借用に縛られるためである。口は呼び出しごとに受け取る。
//! 前の描画の値を配線が持つのは、エンジンのカメラは更新のたびに表示距離を理想距離へ合わせて前の描画の値を残さないためである。
//! 持つ値は2つに分かれる。計器用の直前の描画はどちらの系統の描画でも更新し、復帰と保持の基準にするプレイヤー用が最後に決めた
//! 表示距離はプレイヤー用の描画だけで更新する。デバッグ用の描画で基準を上書きすると、プレイヤー用へ戻した最初の描画の掃引が
//! 評価できないときにデバッグ用の理想距離をそのまま保ち、未読込の中へ視点を出す。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断9」「判断10」

use blitz_game::{カメラの遮蔽と復帰, 世界の形を尋ねる口, 前の描画の表示距離, 遮蔽の判定, 遮蔽の判定の入力};
use blitz_math::{メートル, 大域ワールド位置, 秒};

use super::camera_system::カメラの系統;
use super::instrument::{カメラの計器, 直前の描画のカメラ};
use crate::input::ゲーム操作の適用方針;

/// その描画のカメラの姿勢と、その描画で進めた時間。フレームの工程がエンジンのカメラと時間進行から組む。
pub(crate) struct この描画のカメラの入力 {
    pub(crate) 注視点: 大域ワールド位置,
    pub(crate) 理想視点: 大域ワールド位置,
    pub(crate) 理想距離: メートル,
    pub(crate) 表示距離の下限: メートル,
    pub(crate) 進めた時間: 秒,
}

pub(super) struct プレイヤーカメラの配線 {
    系統: カメラの系統,
    切替の適用方針: ゲーム操作の適用方針, // フレーム数の決まった実行では切替の操作を通さない
    遮蔽と復帰: カメラの遮蔽と復帰,
    直前の描画: 直前の描画のカメラ,                         // 計器用。どちらの系統の描画でも更新する
    プレイヤー用が最後に決めた表示距離: 前の描画の表示距離, // 復帰と保持の基準。プレイヤー用の描画だけで更新する
    完全性で保った描画の数: u32,
}

impl プレイヤーカメラの配線 {
    pub(super) fn プレイヤー用で生成する(切替の適用方針: ゲーム操作の適用方針) -> Self {
        Self {
            系統: カメラの系統::プレイヤー用,
            切替の適用方針,
            遮蔽と復帰: カメラの遮蔽と復帰::初版の値で生成する(),
            直前の描画: 直前の描画のカメラ::まだ描いていない,
            プレイヤー用が最後に決めた表示距離: 前の描画の表示距離::まだ描いていない,
            完全性で保った描画の数: 0,
        }
    }

    /// 切替の操作は1描画に1度、操作入力の確定の直後に受け取る。押した瞬間の操作であり、刻みへは配らない。
    pub(super) fn 切替の操作を受け取る(&mut self, 押した瞬間か: bool) {
        if self.切替の適用方針.カメラの系統の切替を通す(押した瞬間か) {
            self.系統 = self.系統.切り替えた系統();
        }
    }

    pub(super) fn 注視点を足元から求める(&self, 足元: 大域ワールド位置) -> 大域ワールド位置 {
        self.遮蔽と復帰.注視点を足元から求める(足元)
    }

    /// この描画の表示距離。プレイヤー用は遮蔽と復帰の規則で決め、デバッグ用は理想距離のままにする。
    pub(super) fn この描画の表示距離を決める<口: 世界の形を尋ねる口>(
        &mut self,
        口: &mut 口,
        入力: この描画のカメラの入力,
    ) -> Result<メートル, 口::問い合わせエラー> {
        let (表示距離, 判定) = match self.系統 {
            カメラの系統::デバッグ用 => (入力.理想距離, 遮蔽の判定::遮られていない),
            カメラの系統::プレイヤー用 => {
                let 決定 = self.遮蔽と復帰.表示距離を決める(口, self.遮蔽の判定の入力を組む(&入力))?;
                self.プレイヤー用が最後に決めた表示距離 = 前の描画の表示距離::描いた {
                    表示距離: 決定.表示距離(),
                    理想距離: 入力.理想距離,
                };
                (決定.表示距離(), 決定.判定())
            }
        };
        if 判定 == 遮蔽の判定::評価できず前の表示距離を保った {
            self.完全性で保った描画の数 = self.完全性で保った描画の数.saturating_add(1);
        }
        self.直前の描画 = 直前の描画のカメラ::描いた {
            理想距離: 入力.理想距離,
            表示距離,
            判定,
        };
        Ok(表示距離)
    }

    fn 遮蔽の判定の入力を組む(&self, 入力: &この描画のカメラの入力) -> 遮蔽の判定の入力 {
        遮蔽の判定の入力 {
            注視点: 入力.注視点,
            理想視点: 入力.理想視点,
            理想距離: 入力.理想距離,
            表示距離の下限: 入力.表示距離の下限,
            前の表示距離: self.プレイヤー用が最後に決めた表示距離,
            進めた時間: 入力.進めた時間,
        }
    }

    pub(super) fn 計器を作る(&self) -> カメラの計器 {
        カメラの計器 {
            系統: self.系統,
            直前の描画: self.直前の描画,
            完全性で保った描画の数: self.完全性で保った描画の数,
        }
    }
}
