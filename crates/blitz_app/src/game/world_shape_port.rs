//! ゲームロジック層の世界の形を尋ねる口の、コンポジションルート側の実装。エンジンの問い合わせを包み、答えをゲームの語彙へ写す。
//! 答えの写しは`answer_mapping`、拒む理由は`error`、読込済みチャンクの形の出どころは`shape_source`にある。
//!
//! 枝が2つあるのは、ストリーミングを使わない起動が読込済みチャンクを1つも持たないためである。読み込まれていない座標を
//! 覆いが含む問い合わせは、エンジンの候補の選別が「評価できない領域を含む」と答える。空の保管から選別を組むと、
//! 建物を1棟も持たない世界の全ての問い合わせが評価できない側へ落ちるため、その起動では地形だけを相手にする。
//!
//! 描画機会ごとに組んで使い終えたら捨てる。候補の受け皿を配線が持ち越さないのは、候補が読込済みチャンクの形状を
//! 参照で持ち、その参照の寿命がこの描画のストリーミング調停の借用に縛られるためである。空の`Vec`は確保を起こさず、
//! 確保が起きるのは掃引の覆いが読込済みチャンクの建物に触れうる描画だけである。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断3」

mod answer_mapping;
mod error;
mod shape_source;

use blitz_engine::height_field::高さ場の読み口;
use blitz_engine::static_shape::index::静的な子形状の候補;
use blitz_engine::world_shape_query::世界の形への問い合わせ;
use blitz_game::{世界の形を尋ねる口, 掃引の答え, 胴体カプセル};
use blitz_math::{メートル, ワールド, 変位, 大域ワールド位置};

pub(crate) use error::世界の形を尋ねる口の実装エラー;
pub(crate) use shape_source::読込済みチャンクの形の出どころ;

pub(super) enum エンジンの問い合わせを包んだ世界の形を尋ねる口<'世界> {
    地形だけ(&'世界 高さ場の読み口),
    地形と読込済みチャンクの形 {
        問い合わせ: 世界の形への問い合わせ<'世界>,
        受け皿: Vec<静的な子形状の候補<'世界>>,
    },
}

impl<'世界> エンジンの問い合わせを包んだ世界の形を尋ねる口<'世界> {
    pub(super) fn 組む(
        高さ場の読み口: &'世界 高さ場の読み口,
        出どころ: 読込済みチャンクの形の出どころ<'世界>,
    ) -> Result<Self, 世界の形を尋ねる口の実装エラー> {
        match 出どころ {
            読込済みチャンクの形の出どころ::ストリーミングを使わない起動 => Ok(Self::地形だけ(高さ場の読み口)),
            読込済みチャンクの形の出どころ::ストリーミング調停(調停) => Ok(Self::地形と読込済みチャンクの形 {
                問い合わせ: 世界の形への問い合わせ::生成する(高さ場の読み口, 調停.静的世界の候補の選別を作る()?),
                受け皿: Vec::new(),
            }),
        }
    }

    fn 掃引したカプセルの答えを求める(
        &mut self,
        軸の始点: 大域ワールド位置,
        軸の終点: 大域ワールド位置,
        半径: メートル,
        掃引の変位: 変位<ワールド>,
    ) -> Result<掃引の答え, 世界の形を尋ねる口の実装エラー> {
        match self {
            Self::地形だけ(読み口) => answer_mapping::地表の問い合わせ結果を写す(
                読み口.掃引したカプセルが最初に触れる地表を求める(軸の始点, 軸の終点, 半径, 掃引の変位),
            ),
            Self::地形と読込済みチャンクの形 { 問い合わせ, 受け皿 } => answer_mapping::世界の形の答えを写す(
                問い合わせ.掃引したカプセルが最初に触れる世界の形を求める(軸の始点, 軸の終点, 半径, 掃引の変位, 受け皿)?,
            ),
        }
    }
}

impl 世界の形を尋ねる口 for エンジンの問い合わせを包んだ世界の形を尋ねる口<'_> {
    type 問い合わせエラー = 世界の形を尋ねる口の実装エラー;

    fn 掃引した胴体が最初に触れる面を求める(
        &mut self,
        胴体: 胴体カプセル,
        掃引の変位: 変位<ワールド>,
    ) -> Result<掃引の答え, Self::問い合わせエラー> {
        self.掃引したカプセルの答えを求める(胴体.軸の下端の大域位置(), 胴体.軸の上端の大域位置(), 胴体.半径(), 掃引の変位)
    }

    fn 掃引した球が最初に触れる面を求める(
        &mut self,
        中心: 大域ワールド位置,
        半径: メートル,
        掃引の変位: 変位<ワールド>,
    ) -> Result<掃引の答え, Self::問い合わせエラー> {
        self.掃引したカプセルの答えを求める(中心, 中心, 半径, 掃引の変位)
    }
}
