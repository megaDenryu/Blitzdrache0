//! ゲーム状態の台帳へ動く個体を載せる局面と、載せた個体を束の読込へ宣言として渡す局面。
//! いつ呼ばれるか: 前者は起動時の組み立ての1回、後者は束を読み込むたびの1回であり、
//! どちらも毎フレームの位置と向きの書き込み(`entity_ledger`本体)とは呼び出し頻度が違う。
//!
//! 触れるのは台帳の2つの列の追加と読み取りだけであり、既に載っている要素の書き換えは1つも行わない。

use blitz_math::大域ワールド位置;
use blitz_render::frame_input::{動く個体の大域の位置と向きの指定, 読込時の向きから天頂軸まわりに回す角};
use blitz_render::{動く個体の宣言, 描画束ID};

use super::ゲーム状態の台帳;
use crate::game::entity_id::エンティティID;

/// 1体の動く個体が、どの束のどの描画対象のどの個体として描かれるか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 動く個体の描画先 {
    pub(crate) 束id: 描画束ID,
    pub(crate) 描画対象添字: usize,
    pub(crate) 個体添字: u32,
}

impl ゲーム状態の台帳 {
    /// 注意: 同じエンティティIDを二重に登録するのは配線の誤りである。2件目の位置の書き込みが1件目にしか届かず、
    /// 2体目が初期位置から動かない絵になる。到達したらバグであるためpanicで止める。
    pub(in crate::game) fn 動く個体を登録する(
        &mut self,
        エンティティid: エンティティID,
        描画先: 動く個体の描画先,
        初期の位置: 大域ワールド位置,
        初期の回す角: 読込時の向きから天頂軸まわりに回す角,
    ) {
        assert!(
            !self.エンティティid一覧.contains(&エンティティid),
            "同じエンティティID({エンティティid:?})を二重に登録した"
        );
        self.エンティティid一覧.push(エンティティid);
        self.指定一覧.push(動く個体の大域の位置と向きの指定 {
            束id: 描画先.束id,
            描画対象添字: 描画先.描画対象添字,
            個体添字: 描画先.個体添字,
            大域位置: 初期の位置,
            読込時の向きから回す角: 初期の回す角,
        });
    }

    /// 束の読込より前にレンダラーへ渡す、その束の動く個体の宣言。読込の1度だけ呼ぶため、ここでの確保は毎フレームに乗らない。
    pub(in crate::game) fn 束の動く個体の宣言一覧を作る(&self, 束id: 描画束ID) -> Vec<動く個体の宣言> {
        self.指定一覧
            .iter()
            .filter(|指定| 指定.束id == 束id)
            .map(|指定| 動く個体の宣言 {
                描画対象添字: 指定.描画対象添字,
                個体添字: 指定.個体添字,
            })
            .collect()
    }
}
