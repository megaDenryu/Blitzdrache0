//! 動く個体1体ぶんの、前の確定値と現在の確定値の2枚。担当するのは2枚を持つことと、刻みの確定で繰り上げることと、
//! この描画の割合で混ぜた値を答えることだけである。ゲーム状態全体は二重化せず、2枚になるのは供給値だけである。
//!
//! 繰り上げを刻みごとに行うのは、混ぜる2枚が必ず1刻みぶんだけ離れている必要があるためである。描画ごとに1回だけ
//! 繰り上げると、4本進めた描画の2枚が4刻みぶん離れ、1刻みぶんの割合で混ぜた値が2枚の間の正しい位置にならない。
//! 参照: `_doc/設計/時間の規律.md`「判断6」。

use super::supply_value::動く個体の大域の位置と向き;
use crate::app::描画補間の割合;

pub(crate) struct 前と現在の確定値 {
    前: 動く個体の大域の位置と向き,
    現在: 動く個体の大域の位置と向き,
}

impl 前と現在の確定値 {
    /// 登録時に使う。2枚を同じ値にするため、最初の刻みが確定するまでどの割合で混ぜても値が動かない。
    pub(in crate::game) fn どちらも同じ値で始める(確定値: 動く個体の大域の位置と向き) -> Self {
        Self {
            前: 確定値, 現在: 確定値
        }
    }

    /// 1刻みの確定を受け、現在の確定値を前へ繰り上げて新しい確定値を現在へ据える。
    pub(in crate::game) fn 刻みの確定値を繰り上げて据える(&mut self, 確定値: 動く個体の大域の位置と向き) {
        self.前 = self.現在;
        self.現在 = 確定値;
    }

    /// 位置を跳ばしたときに2枚とも据え直す。繰り上げで据えると、跳ぶ前と跳んだ先を混ぜた値が1描画だけ描かれ、
    /// 個体が跳んだ距離の途中のどこかに現れる。
    pub(in crate::game) fn どちらも据え直す(&mut self, 確定値: 動く個体の大域の位置と向き) {
        self.前 = 確定値;
        self.現在 = 確定値;
    }

    /// この描画の割合で混ぜた値。現在の確定値そのものを表す割合では、現在の確定値を1ビットも変えずに返す。
    pub(in crate::game) fn 割合で混ぜる(&self, 割合: 描画補間の割合) -> 動く個体の大域の位置と向き {
        self.現在.相手の側へ係数ぶん寄せる(self.前, 割合.前の確定値の側へ戻す係数())
    }
}
