//! 動く個体1体ぶんの、描画へ渡す連続量。担当するのは大域の位置と向きを1組で持つことと、相手の値の側へ
//! 係数ぶん寄せた値を答えることだけであり、どの描画対象の値かも、いつ書き換わるかも知らない。
//!
//! 束IDと描画対象添字と個体添字を持たないのは、描画補間が混ぜてよいのが見た目の連続量だけであり、
//! どの個体を指すかが混ぜる対象でないためである。混ぜてはならない量をこの型へ入れないことが、
//! 補間してよい量と補間してはならない量の区別を運用でなく型で保つ手段になる。
//! 参照: `_doc/設計/時間の規律.md`「判断6」。

use blitz_math::大域ワールド位置;
use blitz_render::frame_input::読込時の向きから天頂軸まわりに回す角;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 動く個体の大域の位置と向き {
    大域位置: 大域ワールド位置,
    読込時の向きから回す角: 読込時の向きから天頂軸まわりに回す角,
}

impl 動く個体の大域の位置と向き {
    pub(in crate::game) fn 生成する(
        大域位置: 大域ワールド位置, 読込時の向きから回す角: 読込時の向きから天頂軸まわりに回す角
    ) -> Self {
        Self {
            大域位置,
            読込時の向きから回す角,
        }
    }

    pub(in crate::game) fn 大域位置(self) -> 大域ワールド位置 {
        self.大域位置
    }

    pub(in crate::game) fn 読込時の向きから回す角(self) -> 読込時の向きから天頂軸まわりに回す角 {
        self.読込時の向きから回す角
    }

    /// 相手の値の側へ係数ぶん寄せた値。位置は線形に、向きは最短の弧で寄せる。
    /// 係数0ではこの値を1ビットも変えずに返すため、混ぜない描画の絵が補間の導入前と一致する。
    pub(in crate::game) fn 相手の側へ係数ぶん寄せる(self, 相手: Self, 係数: f32) -> Self {
        Self {
            大域位置: self.大域位置.相手の側へ係数ぶん寄せる(相手.大域位置, 係数),
            読込時の向きから回す角: self
                .読込時の向きから回す角
                .最短の弧で相手の側へ係数ぶん寄せる(相手.読込時の向きから回す角, 係数),
        }
    }
}
