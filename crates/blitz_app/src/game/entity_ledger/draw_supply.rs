//! 描画機会ごとに走る台帳の局面。前と現在の確定値をその描画の割合で混ぜて指定の列を作り直し、その列を描画へ預けて戻す。
//! いつ呼ばれるか: 1描画に1度であり、刻みごとの確定値の書き込み(`entity_ledger`本体)とは呼び出し頻度が違う。
//!
//! 触れるのは`確定値一覧`の読み取りと`指定一覧`の書き換えだけであり、確定値の繰り上げは1つも行わない。
//! 刻みを1本も進めない描画でも混ぜ直すのは、2枚が据え置きのままでも割合だけが進み、描く位置が動くためである。
//! 参照: `_doc/設計/時間の規律.md`「判断6」。

use blitz_math::大域ワールド位置;
use blitz_render::frame_input::動く個体の大域の位置と向きの指定;

use super::ゲーム状態の台帳;
use crate::app::描画補間の割合;
use crate::game::entity_id::エンティティID;

impl ゲーム状態の台帳 {
    /// 描画へ渡す指定の列を、前と現在の確定値をこの描画の割合で混ぜた値へ作り直す。
    ///
    /// 注意: 指定の列を描画へ預けている間に呼ぶと混ぜる先が無い。件数の食い違いとしてpanicで止める。
    pub(in crate::game) fn 描画へ渡す指定一覧をこの描画の割合で混ぜ直す(&mut self, 割合: 描画補間の割合) {
        assert_eq!(
            self.指定一覧.len(),
            self.確定値一覧.len(),
            "指定一覧を描画へ預けている間に混ぜ直そうとした"
        );
        for (確定値, 指定) in self.確定値一覧.iter().zip(self.指定一覧.iter_mut()) {
            let 混ぜた値 = 確定値.割合で混ぜる(割合);
            指定.大域位置 = 混ぜた値.大域位置();
            指定.読込時の向きから回す角 = 混ぜた値.読込時の向きから回す角();
        }
    }

    /// カメラの注視点が追う、この描画の割合で混ぜた大域位置。描くその個体と同じ値になる。
    /// 登録していないエンティティを指すのは配線の誤りであるためpanicで止める。
    pub(in crate::game) fn エンティティの混ぜた大域位置を求める(
        &self,
        エンティティid: エンティティID,
        割合: 描画補間の割合,
    ) -> 大域ワールド位置 {
        for (登録済み, 確定値) in self.エンティティid一覧.iter().zip(self.確定値一覧.iter()) {
            if *登録済み == エンティティid {
                return 確定値.割合で混ぜる(割合).大域位置();
            }
        }
        panic!("エンティティID({エンティティid:?})の混ぜた大域位置を求められない。台帳に未登録である");
    }

    /// 描画入力が借用する指定の列をアプリの外へ預ける。確保した容量を次のフレームへ持ち越すため、描画の成否によらず戻す。
    pub(in crate::game) fn 指定一覧を預ける(&mut self) -> Vec<動く個体の大域の位置と向きの指定> {
        std::mem::take(&mut self.指定一覧)
    }

    pub(in crate::game) fn 指定一覧を戻す(&mut self, 受け皿: Vec<動く個体の大域の位置と向きの指定>) {
        self.指定一覧 = 受け皿;
    }
}
