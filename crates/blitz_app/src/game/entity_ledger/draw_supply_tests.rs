//! 描画補間で混ぜた供給値の検証。台帳へ1体だけ登録し、刻みの確定と描画の混ぜを直に叩く。
//! 実時間もレンダラーも1つも使わないため、どの計算機で何度走らせても同じ結果になる。

use blitz_math::{ラジアン, 大域メートル, 大域ワールド位置};
use blitz_render::frame_input::読込時の向きから天頂軸まわりに回す角;

use super::{ゲーム状態の台帳, 動く個体の描画先};
use crate::app::scene_load::起動時シーンの束ID;
use crate::app::描画補間の割合;
use crate::game::entity_id::エンティティID;

const 検証のエンティティID: エンティティID = エンティティID::生成する(0);

fn 東へ何メートルかの位置(東へ: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(東へ), 大域メートル::生成する(0.0), 大域メートル::生成する(0.0))
}

fn 角(度: f32) -> 読込時の向きから天頂軸まわりに回す角 {
    読込時の向きから天頂軸まわりに回す角::生成する(ラジアン::度から(度))
}

fn 原点に1体だけ登録した台帳() -> ゲーム状態の台帳 {
    let mut 台帳 = ゲーム状態の台帳::動く個体を1体も持たない台帳を作る();
    台帳.動く個体を登録する(
        検証のエンティティID,
        動く個体の描画先 {
            束id: 起動時シーンの束ID,
            描画対象添字: 0,
            個体添字: 0,
        },
        東へ何メートルかの位置(0.0),
        角(0.0),
    );
    台帳
}

fn 中点で混ぜる割合() -> 描画補間の割合 {
    描画補間の割合::前の確定値から進んだ割合として作る(0.5)
}

fn 混ぜた東へのメートル(台帳: &ゲーム状態の台帳, 割合: 描画補間の割合) -> f64 {
    台帳.エンティティの混ぜた大域位置を求める(検証のエンティティID, 割合).x().値()
}

/// 反証: ここが現在の確定値そのものにならないと、フレーム数の決まった実行の絵が1刻みぶん遅れ、
/// 補間の導入だけで既存のスモークと検収の読み戻しが変わる。
#[test]
fn 現在の確定値そのものの割合では現在の確定値が1ビットも変わらずに出る() {
    let mut 台帳 = 原点に1体だけ登録した台帳();
    台帳.刻みで確定した大域の位置と向きを書き込む(検証のエンティティID, 東へ何メートルかの位置(10.0), 角(90.0));
    let 混ぜた位置 = 台帳.エンティティの混ぜた大域位置を求める(検証のエンティティID, 描画補間の割合::現在の確定値そのもの());
    assert_eq!(混ぜた位置, 東へ何メートルかの位置(10.0));
}

#[test]
fn 余りが基本刻みの半分の割合では2枚の中点が出る() {
    let mut 台帳 = 原点に1体だけ登録した台帳();
    台帳.刻みで確定した大域の位置と向きを書き込む(検証のエンティティID, 東へ何メートルかの位置(10.0), 角(0.0));
    assert!((混ぜた東へのメートル(&台帳, 中点で混ぜる割合()) - 5.0).abs() < 1.0e-9);
}

/// 反証: 刻みごとに繰り上げないと、4本進めた描画の2枚が4刻みぶん離れ、1刻みぶんの割合で混ぜた値が
/// 2枚の間の正しい位置にならない。
#[test]
fn 刻みごとに繰り上がるため混ぜる2枚は常に1刻みぶんだけ離れる() {
    let mut 台帳 = 原点に1体だけ登録した台帳();
    for 東へ in 1..=4 {
        台帳.刻みで確定した大域の位置と向きを書き込む(検証のエンティティID, 東へ何メートルかの位置(f64::from(東へ)), 角(0.0));
    }
    assert!((混ぜた東へのメートル(&台帳, 中点で混ぜる割合()) - 3.5).abs() < 1.0e-9);
}

/// 反証: 混ぜる工程が確定値を書き換えると、刻みを1本も進めない描画のたびに位置が前へずれていく。
#[test]
fn 刻みを進めない描画で何度混ぜても2枚は繰り上がらない() {
    let mut 台帳 = 原点に1体だけ登録した台帳();
    台帳.刻みで確定した大域の位置と向きを書き込む(検証のエンティティID, 東へ何メートルかの位置(10.0), 角(0.0));
    for _ in 0..8 {
        台帳.描画へ渡す指定一覧をこの描画の割合で混ぜ直す(中点で混ぜる割合());
    }
    assert!((混ぜた東へのメートル(&台帳, 中点で混ぜる割合()) - 5.0).abs() < 1.0e-9);
}

/// 反証: 跳びを繰り上げで据えると、跳ぶ前と跳んだ先を混ぜた位置が1描画だけ描かれ、個体が跳んだ距離の途中に現れる。
#[test]
fn 跳ばした位置を前後とも据え直すとどの割合でも跳んだ先だけが出る() {
    let mut 台帳 = 原点に1体だけ登録した台帳();
    台帳.跳ばした大域の位置と向きを前後とも据え直す(検証のエンティティID, 東へ何メートルかの位置(1000.0), 角(0.0));
    assert!((混ぜた東へのメートル(&台帳, 中点で混ぜる割合()) - 1000.0).abs() < 1.0e-9);
}
