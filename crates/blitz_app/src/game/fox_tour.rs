//! クソゲー1本目「キツネの場所巡り」の配線を所有する。道順・ゲームの状態・操作の適用方針・ゲーム状態の台帳・更新の回数を
//! 1つに束ね、1刻みぶんの更新をこの型のメソッドで行う。
//!
//! 道順はゲーム側の表から作る。検収のための世界の分岐はこの配線を通らない。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断4」。
//! 起動時に1度だけ走る組み立てとプレイヤーの描画先の決め方は`create`にあり、
//! 高さ場を据えることと足元の地面の高さを求めることは`ground`にあり、
//! キツネが読込時に向いている方位と描画側への向きの写しは`facing`にある。

mod create;
pub(super) mod facing;
mod ground;
#[cfg(test)]
mod ground_tests;

use blitz_engine::height_field::高さ場の読み口;
use blitz_game::{
    ゲームインテント, 前へ進む向きの方位角, 場所巡りのゲームの状態, 場所巡りの道順, 確定済みの操作入力
};
use blitz_math::{大域ワールド位置, 秒};

use super::entity_ledger::ゲーム状態の台帳;
use super::scripted_operation::更新回数から台本の操作入力を決める;
use super::summary::ゲーム進行の要約;
use crate::app::描画補間の割合;
use crate::cli::{ゲーム操作の出どころ, 遊ぶゲームの指定};
use crate::input::ゲーム操作の適用方針;
use crate::overlay_ui::ゲーム画面の表示内容;

/// 型の可視性だけをクレート全体へ開くのは、ゲーム配線の枝が保持するためである。操作はすべて`pub(super)`であり、`crate::game`の外からは呼べない。
pub(crate) struct キツネの場所巡りの配線 {
    道順: 場所巡りの道順,
    状態: 場所巡りのゲームの状態,
    操作の適用方針: ゲーム操作の適用方針,
    操作の出どころ: ゲーム操作の出どころ,
    台帳: ゲーム状態の台帳,
    ゲーム更新の回数: u32,
    高さ場の読み口: 高さ場の読み口,
}

impl キツネの場所巡りの配線 {
    /// 確定済みの操作入力をこのゲームの意味へ写し、方針に通してから1刻みだけ状態を進める。
    pub(super) fn 一刻み進める(
        &mut self, 操作入力: 確定済みの操作入力, 前へ進む向き: 前へ進む向きの方位角, 一刻みの秒: 秒
    ) {
        // 台本の操作は適用方針を通らない。方針が止めるのは実ウィンドウから届く操作であり、台本は検収が自ら与える決定的な操作である。
        let インテント = match 更新回数から台本の操作入力を決める(self.操作の出どころ, self.ゲーム更新の回数) {
            Some(台本の操作入力) => ゲームインテント::確定済みの操作入力から写す(台本の操作入力),
            None => self.操作の適用方針.通す(ゲームインテント::確定済みの操作入力から写す(操作入力)),
        };
        self.状態 = self.状態.一刻み進めた状態を返す(&self.道順, インテント, 一刻みの秒, 前へ進む向き);
        // 接地は移動の後に置く。移動した先の高さを読むためであり、移動の前に読むと1フレーム前の位置の高さが付く。
        self.状態 = self.状態.足元の地面の高さを反映した状態を返す(self.足元の地面の高さを求める());
        let エンティティid = self.プレイヤーのエンティティid();
        self.台帳.刻みで確定した大域の位置と向きを書き込む(
            エンティティid,
            self.状態.プレイヤーの大域位置(),
            facing::世界での向きを読込時からの回転角へ写す(self.状態.プレイヤーの向き()),
        );
        self.ゲーム更新の回数 = self.ゲーム更新の回数.saturating_add(1);
    }

    pub(super) fn 台帳(&self) -> &ゲーム状態の台帳 {
        &self.台帳
    }

    pub(super) fn 台帳を借りる(&mut self) -> &mut ゲーム状態の台帳 {
        &mut self.台帳
    }

    pub(super) fn プレイヤーの大域位置(&self) -> 大域ワールド位置 {
        self.状態.プレイヤーの大域位置()
    }

    pub(super) fn カメラが追従する混ぜた大域位置(&self, 割合: 描画補間の割合) -> 大域ワールド位置 {
        self.台帳.エンティティの混ぜた大域位置を求める(self.プレイヤーのエンティティid(), 割合)
    }

    pub(super) fn 終了が決まったか(&self) -> bool {
        self.状態.終了が決まったか()
    }

    /// そのフレームにゲームの画面が出す値。進行段階と巡った数だけを写し、位置も時刻も渡さない。
    pub(super) fn 画面へ重ねる表示内容を作る(&self) -> ゲーム画面の表示内容 {
        ゲーム画面の表示内容 {
            進行段階: self.状態.進行段階(),
            到達済みの目的地数: self.状態.場所巡り().到達済みの目的地数(),
            目的地の総数: self.道順.目的地の総数(),
        }
    }

    pub(super) fn 進行の要約を作る(&self) -> ゲーム進行の要約 {
        ゲーム進行の要約 {
            ゲームの表示名: 遊ぶゲームの指定::キツネの場所巡り(self.操作の出どころ).表示名(),
            ゲーム更新の回数: self.ゲーム更新の回数,
            最後の進行段階の呼び名: self.状態.進行段階().呼び名(),
            到達済みの目的地数: self.状態.場所巡り().到達済みの目的地数(),
            目的地の総数: self.道順.目的地の総数(),
            プレイヤーの大域位置: self.状態.プレイヤーの大域位置(),
        }
    }
}
