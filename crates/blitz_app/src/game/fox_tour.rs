/// 型の可視性だけをクレート全体へ開くのは、ゲーム配線の枝が保持するためである。操作はすべて`pub(super)`であり、`crate::game`の外からは呼べない。
pub(crate) struct キツネの場所巡りの配線 {
    道順: 場所巡りの道順,
    状態: 場所巡りのゲームの状態,
    操作の適用方針: ゲーム操作の適用方針,
    操作の出どころ: ゲーム操作の出どころ,
    台帳: ゲーム状態の台帳,
    ゲーム更新の回数: u32,
    高さ場の読み口: 高さ場の読み口,
    カメラ: プレイヤーカメラの配線,
    移動の記録: 移動の観測の記録,
}

impl キツネの場所巡りの配線 {
    /// 確定済みの操作入力をこのゲームの意味へ写し、方針に通してから1刻みだけ状態を進める。
    /// 世界の形を尋ねる口は刻みごとに組み、使い終えたら捨てる(口がその描画のストリーミング調停の借用に縛られるためである)。
    pub(super) fn 一刻み進める(
        &mut self,
        出どころ: 読込済みチャンクの形の出どころ<'_>,
        操作入力: 確定済みの操作入力,
        前へ進む向き: 前へ進む向きの方位角,
        一刻みの秒: 秒,
    ) -> Result<(), 世界の形を尋ねる口の実装エラー> {
        // 台本の操作は適用方針を通らない。方針が止めるのは実ウィンドウから届く操作であり、台本は検収が自ら与える決定的な操作である。
        let インテント = match 更新回数から台本の操作入力を決める(self.操作の出どころ, self.ゲーム更新の回数) {
            Some(台本の操作入力) => ゲームインテント::確定済みの操作入力から写す(台本の操作入力),
            None => self.操作の適用方針.通す(ゲームインテント::確定済みの操作入力から写す(操作入力)),
        };
        let 入力 = 一刻みの移動の入力 {
            インテント,
            刻み: 一刻みの秒,
            前へ進む向き,
        };
        let mut 口 = エンジンの問い合わせを包んだ世界の形を尋ねる口::組む(&self.高さ場の読み口, 出どころ)?;
        let (状態, 観測) = self.状態.一刻み進めた状態を返す(&mut 口, &self.道順, &入力)?;
        drop(口);
        self.状態 = 状態;
        self.移動の記録.刻みの観測を記録する(観測);
        let エンティティid = self.プレイヤーのエンティティid();
        self.台帳.刻みで確定した大域の位置と向きを書き込む(
            エンティティid,
            self.状態.プレイヤーの大域位置(),
            facing::世界での向きを読込時からの回転角へ写す(self.状態.プレイヤーの向き()),
        );
        self.ゲーム更新の回数 = self.ゲーム更新の回数.saturating_add(1);
        Ok(())
    }

    pub(super) fn 終了が決まったか(&self) -> bool {
        self.状態.終了が決まったか()
    }
}
