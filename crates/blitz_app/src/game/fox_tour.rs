//! クソゲー1本目「キツネの場所巡り」の配線を所有する。道順・ゲームの状態・操作の適用方針・ゲーム状態の台帳・更新の回数・
//! 移動の観測の記録を1つに束ね、1刻みぶんの更新をこの型のメソッドで行う。
//!
//! 道順はゲーム側の表から作る。検収のための世界の分岐はこの配線を通らない。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断4」。
//! 起動時に1度だけ走る組み立てとプレイヤーの描画先の決め方は`create`にあり、
//! 高さ場を据えることと据えた高さ場の地表へ足元と目的地を置くことは`ground`にあり、
//! キツネが読込時に向いている方位と描画側への向きの写しは`facing`にあり、
//! 台帳・カメラ・移動の記録・要約を外へ渡す口は`supply`にある。

