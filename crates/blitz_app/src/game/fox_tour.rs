//! クソゲー1本目「キツネの場所巡り」の配線を所有する。道順・ゲームの状態・操作の適用方針・ゲーム状態の台帳・更新の回数を
//! 1つに束ね、1刻みぶんの更新をこの型のメソッドで行う。
//!
//! 道順はゲーム側の表から作る。検収のための世界の分岐はこの配線を通らない。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断4」。

use blitz_game::{
    キツネの場所巡りの道順を作る, ゲームインテント, 場所巡りのゲームの状態, 場所巡りの道順, 確定済みの操作入力
};
use blitz_math::大域ワールド位置;

use super::entity_id::エンティティID;
use super::entity_ledger::{ゲーム状態の台帳, 動く個体の描画先};
use super::step_seconds::ゲーム更新の一刻みの秒;
use super::summary::ゲーム進行の要約;
use crate::app::scene_load::起動時シーンの束ID;
use crate::cli::{起動モード, 遊ぶゲームの指定};
use crate::input::ゲーム操作の適用方針;

/// プレイヤーのエンティティID。動く個体が1体だけの1本目では、台帳に載るのはこの1件である。
const プレイヤーのエンティティID: エンティティID = エンティティID::生成する(0);
/// プレイヤーを描く描画対象の、起動時シーンの束の中での並び順。スキニングは束の先頭の描画対象だけへ適用されるため(判断44)、
/// スキン付きのキツネは常にこの位置に来る。
const プレイヤーを描く描画対象添字: usize = 0;
/// キツネの描画対象の個体変換列の中での個体の並び順。スキン付きの描画対象は個体を1体だけ持つ。
const プレイヤーの個体添字: u32 = 0;

/// 型の可視性だけをクレート全体へ開くのは、ゲーム配線の枝が保持するためである。操作はすべて`pub(super)`であり、`crate::game`の外からは呼べない。
pub(crate) struct キツネの場所巡りの配線 {
    道順: 場所巡りの道順,
    状態: 場所巡りのゲームの状態,
    操作の適用方針: ゲーム操作の適用方針,
    台帳: ゲーム状態の台帳,
    ゲーム更新の回数: u32,
}

impl キツネの場所巡りの配線 {
    /// 出発地点は世界の原点である。地形の高さを実行中に参照する経路が入るまでは、高さを0に置く。
    pub(super) fn 生成する(モード: 起動モード) -> Self {
        let 出発地点 = 大域ワールド位置::原点();
        let mut 台帳 = ゲーム状態の台帳::動く個体を1体も持たない台帳を作る();
        台帳.動く個体を登録する(
            プレイヤーのエンティティID,
            動く個体の描画先 {
                束id: 起動時シーンの束ID,
                描画対象添字: プレイヤーを描く描画対象添字,
                個体添字: プレイヤーの個体添字,
            },
            出発地点,
        );
        Self {
            道順: キツネの場所巡りの道順を作る(),
            状態: 場所巡りのゲームの状態::開始時の状態を作る(出発地点),
            操作の適用方針: ゲーム操作の適用方針::起動モードから決める(モード),
            台帳,
            ゲーム更新の回数: 0,
        }
    }

    /// 確定済みの操作入力をこのゲームの意味へ写し、方針に通してから1刻みだけ状態を進める。
    pub(super) fn 一刻み進める(&mut self, 操作入力: 確定済みの操作入力) {
        let インテント = self.操作の適用方針.通す(ゲームインテント::確定済みの操作入力から写す(操作入力));
        self.状態 = self.状態.一刻み進めた状態を返す(&self.道順, インテント, ゲーム更新の一刻みの秒());
        self.台帳
            .エンティティの大域位置を書き込む(プレイヤーのエンティティID, self.状態.プレイヤーの大域位置());
        self.ゲーム更新の回数 = self.ゲーム更新の回数.saturating_add(1);
    }

    pub(super) fn 台帳(&self) -> &ゲーム状態の台帳 {
        &self.台帳
    }

    pub(super) fn 台帳を借りる(&mut self) -> &mut ゲーム状態の台帳 {
        &mut self.台帳
    }

    pub(super) fn プレイヤーの大域位置(&self) -> 大域ワールド位置 {
        self.状態.プレイヤーの大域位置()
    }

    pub(super) fn 終了が決まったか(&self) -> bool {
        self.状態.終了が決まったか()
    }

    pub(super) fn 進行の要約を作る(&self) -> ゲーム進行の要約 {
        ゲーム進行の要約 {
            ゲームの表示名: 遊ぶゲームの指定::キツネの場所巡り.表示名(),
            ゲーム更新の回数: self.ゲーム更新の回数,
            最後の進行段階の呼び名: self.状態.進行段階().呼び名(),
            到達済みの目的地数: self.状態.場所巡り().到達済みの目的地数(),
            目的地の総数: self.道順.目的地の総数(),
        }
    }
}
