//! 目的地も進行段階も持たず、キツネの移動・接地・カメラ追従だけを配線するゲーム。高さ場を据えることは`ground`にある。

mod ground;

use blitz_engine::height_field::高さ場の読み口;
use blitz_game::{
    ゲームインテント, 一刻みの移動の入力, 前へ進む向きの方位角, 歩くだけのゲームの状態, 確定済みの操作入力
};
use blitz_math::{大域ワールド位置, 秒};

use super::camera_wiring::プレイヤーカメラの配線;
use super::entity_ledger::ゲーム状態の台帳;
use super::fox_player::{プレイヤーのエンティティID, 原点のキツネを登録した台帳を作る};
use super::fox_tour::facing::{キツネが読込時に向いている方位角, 世界での向きを読込時からの回転角へ写す};
use super::instrument::移動の計器;
use super::movement_record::移動の観測の記録;
use super::world_shape_port::{
    エンジンの問い合わせを包んだ世界の形を尋ねる口, 世界の形を尋ねる口の実装エラー, 読込済みチャンクの形の出どころ
};
use crate::app::描画補間の割合;
use crate::cli::起動モード;
use crate::input::ゲーム操作の適用方針;

pub(crate) struct 歩くだけの配線 {
    状態: 歩くだけのゲームの状態,
    操作の適用方針: ゲーム操作の適用方針,
    台帳: ゲーム状態の台帳,
    高さ場の読み口: 高さ場の読み口,
    カメラ: プレイヤーカメラの配線,
    移動の記録: 移動の観測の記録,
}

impl 歩くだけの配線 {
    pub(super) fn 生成する(モード: 起動モード) -> Self {
        let 操作の適用方針 = ゲーム操作の適用方針::起動モードから決める(モード);
        Self {
            状態: 歩くだけのゲームの状態::開始時の状態を作る(大域ワールド位置::原点(), キツネが読込時に向いている方位角()),
            操作の適用方針,
            台帳: 原点のキツネを登録した台帳を作る(),
            高さ場の読み口: 高さ場の読み口::高さ場を持たない世界,
            カメラ: プレイヤーカメラの配線::プレイヤー用で生成する(操作の適用方針),
            移動の記録: 移動の観測の記録::まだ刻んでいない記録を作る(),
        }
    }

    /// 世界の形を尋ねる口は刻みごとに組み、使い終えたら捨てる(口がその描画のストリーミング調停の借用に縛られるためである)。
    pub(super) fn 一刻み進める(
        &mut self,
        出どころ: 読込済みチャンクの形の出どころ<'_>,
        操作入力: 確定済みの操作入力,
        前へ進む向き: 前へ進む向きの方位角,
        一刻みの秒: 秒,
    ) -> Result<(), 世界の形を尋ねる口の実装エラー> {
        let 入力 = 一刻みの移動の入力 {
            インテント: self.操作の適用方針.通す(ゲームインテント::確定済みの操作入力から写す(操作入力)),
            刻み: 一刻みの秒,
            前へ進む向き,
        };
        let mut 口 = エンジンの問い合わせを包んだ世界の形を尋ねる口::組む(&self.高さ場の読み口, 出どころ)?;
        let (状態, 観測) = self.状態.一刻み進めた状態を返す(&mut 口, &入力)?;
        drop(口);
        self.状態 = 状態;
        self.移動の記録.刻みの観測を記録する(観測);
        let プレイヤー = self.状態.プレイヤーの位置と向き();
        self.台帳.刻みで確定した大域の位置と向きを書き込む(
            プレイヤーのエンティティID,
            プレイヤー.大域位置(),
            世界での向きを読込時からの回転角へ写す(プレイヤー.向き()),
        );
        Ok(())
    }

    pub(super) fn 台帳(&self) -> &ゲーム状態の台帳 {
        &self.台帳
    }

    pub(super) fn 台帳を借りる(&mut self) -> &mut ゲーム状態の台帳 {
        &mut self.台帳
    }

    pub(super) fn プレイヤーの大域位置(&self) -> 大域ワールド位置 {
        self.状態.プレイヤーの位置と向き().大域位置()
    }

    pub(super) fn カメラの注視点にする混ぜた大域位置(&self, 割合: 描画補間の割合) -> 大域ワールド位置 {
        self.カメラ
            .注視点を足元から求める(self.台帳.エンティティの混ぜた大域位置を求める(プレイヤーのエンティティID, 割合))
    }

    pub(super) fn カメラ(&self) -> &プレイヤーカメラの配線 {
        &self.カメラ
    }

    pub(super) fn カメラを借りる(&mut self) -> &mut プレイヤーカメラの配線 {
        &mut self.カメラ
    }

    pub(super) fn カメラと高さ場の読み口を借りる(&mut self) -> (&mut プレイヤーカメラの配線, &高さ場の読み口) {
        (&mut self.カメラ, &self.高さ場の読み口)
    }

    pub(super) fn 移動の記録を借りる(&mut self) -> &mut 移動の観測の記録 {
        &mut self.移動の記録
    }

    pub(super) fn 移動の計器を作る(&self) -> 移動の計器 {
        self.移動の記録.計器を作る(self.状態.プレイヤーの移動状態())
    }
}
