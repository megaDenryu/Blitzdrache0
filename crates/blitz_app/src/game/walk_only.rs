//! 目的地も進行段階も持たず、キツネの移動・接地・カメラ追従だけを配線するゲーム。

use blitz_engine::height_field::高さ場の読み口;
use blitz_game::{
    ゲームインテント, 前へ進む向きの方位角, 歩くだけのゲームの状態, 確定済みの操作入力, 足元の地面の高さ
};
use blitz_math::{ラジアン, 大域ワールド位置, 秒};

use super::entity_ledger::ゲーム状態の台帳;
use super::fox_player::{プレイヤーのエンティティID, 原点のキツネを登録した台帳を作る};
use super::fox_tour::facing::{キツネが読込時に向いている方位角, 世界での向きを読込時からの回転角へ写す};
use crate::app::描画補間の割合;
use crate::cli::起動モード;
use crate::input::ゲーム操作の適用方針;

pub(crate) struct 歩くだけの配線 {
    状態: 歩くだけのゲームの状態,
    操作の適用方針: ゲーム操作の適用方針,
    台帳: ゲーム状態の台帳,
    高さ場の読み口: 高さ場の読み口,
}

impl 歩くだけの配線 {
    pub(super) fn 生成する(モード: 起動モード) -> Self {
        Self {
            状態: 歩くだけのゲームの状態::開始時の状態を作る(大域ワールド位置::原点(), キツネが読込時に向いている方位角()),
            操作の適用方針: ゲーム操作の適用方針::起動モードから決める(モード),
            台帳: 原点のキツネを登録した台帳を作る(),
            高さ場の読み口: 高さ場の読み口::高さ場を持たない世界,
        }
    }

    pub(super) fn 一刻み進める(&mut self, 操作入力: 確定済みの操作入力, カメラのヨー: ラジアン, 一刻みの秒: 秒) {
        let インテント = self.操作の適用方針.通す(ゲームインテント::確定済みの操作入力から写す(操作入力));
        self.状態 = self
            .状態
            .一刻み進めた状態を返す(インテント, 一刻みの秒, 前へ進む向きの方位角::生成する(カメラのヨー));
        self.状態 = self.状態.足元の地面の高さを反映した状態を返す(self.足元の地面の高さを求める());
        let プレイヤー = self.状態.プレイヤーの位置と向き();
        self.台帳.刻みで確定した大域の位置と向きを書き込む(
            プレイヤーのエンティティID,
            プレイヤー.大域位置(),
            世界での向きを読込時からの回転角へ写す(プレイヤー.向き()),
        );
    }

    /// 世界の中心へ置き直すのは刻みを1つも進めない跳びであるため、台帳の2枚を前後とも据え直す。
    /// 繰り上げで据えると、原点と世界の中心の間を混ぜた位置が1描画だけ描かれる。
    pub(super) fn 高さ場を据える(&mut self, 読み口: 高さ場の読み口) {
        if let Some(中心) = 読み口.世界の中心の水平位置() {
            let 向き = self.状態.プレイヤーの位置と向き().向き();
            self.状態 = 歩くだけのゲームの状態::開始時の状態を作る(中心, 向き);
        }
        self.高さ場の読み口 = 読み口;
        self.状態 = self.状態.足元の地面の高さを反映した状態を返す(self.足元の地面の高さを求める());
        let プレイヤー = self.状態.プレイヤーの位置と向き();
        self.台帳.跳ばした大域の位置と向きを前後とも据え直す(
            プレイヤーのエンティティID,
            プレイヤー.大域位置(),
            世界での向きを読込時からの回転角へ写す(プレイヤー.向き()),
        );
    }

    fn 足元の地面の高さを求める(&self) -> 足元の地面の高さ {
        let 位置 = self.状態.プレイヤーの位置と向き().大域位置();
        super::ground_height::足元の地面の高さへ写す(self.高さ場の読み口.大域の水平位置から地表高さを求める(位置))
    }

    pub(super) fn 台帳(&self) -> &ゲーム状態の台帳 {
        &self.台帳
    }
    pub(super) fn 台帳を借りる(&mut self) -> &mut ゲーム状態の台帳 {
        &mut self.台帳
    }
    pub(super) fn プレイヤーの大域位置(&self) -> 大域ワールド位置 {
        self.状態.プレイヤーの位置と向き().大域位置()
    }

    pub(super) fn カメラが追従する混ぜた大域位置(&self, 割合: 描画補間の割合) -> 大域ワールド位置 {
        self.台帳.エンティティの混ぜた大域位置を求める(プレイヤーのエンティティID, 割合)
    }
}
