//! ゲーム配線が描画側へ値を渡す面。担当するのは、束の読込より前に渡す動く個体の宣言、そのフレームの動く個体の位置、
//! カメラが追従する位置、画面へ重ねるUIが出す値である。触れるのはゲームの状態と台帳だけであり、
//! 進行段階の判断も入力の確定も持たない。
//!
//! 位置を渡す口が2つに分かれるのは、読む相手が求める時間意味が違うためである。カメラの注視点は描画機会ごとの値であり
//! 混ぜた位置を読み、ストリーミングの必要チャンク集合の中心は刻み境界の確定位置を読む
//! (参照: `_doc/設計/時間の規律.md`「判断5」「判断6」)。
//!
//! ゲームの側からカメラの型を名指ししないため、返すのは大域位置であってカメラの姿勢ではない。カメラへ据えるのは
//! コンポジションルートの配線が行う(参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「第1段階の定義」の項目5)。

use blitz_math::大域ワールド位置;
use blitz_render::frame_input::動く個体の大域の位置と向きの指定;
use blitz_render::{レンダラーエラー, 描画シーン素材, 描画束ID};

use super::ゲーム配線;
use crate::app::描画補間の割合;
use crate::overlay_ui::ゲーム画面の表示内容;

impl ゲーム配線 {
    /// 束の読込より前に、その束の描画シーン素材へ動く個体を宣言する。遊ばない起動では1件も宣言せず、
    /// 全描画対象が読込時に一度だけ書く静的な個体変換のままになる。
    pub(crate) fn 束の描画シーン素材へ動く個体を宣言する(
        &self,
        束id: 描画束ID,
        描画シーン: &mut 描画シーン素材,
    ) -> Result<(), レンダラーエラー> {
        let 台帳 = match self {
            Self::ゲームを遊ばない => return Ok(()),
            Self::キツネの場所巡り(配線) => 配線.台帳(),
            Self::歩くだけ(配線) => 配線.台帳(),
        };
        for 宣言 in 台帳.束の動く個体の宣言一覧を作る(束id) {
            描画シーン.動く個体を宣言する(宣言)?;
        }
        Ok(())
    }

    /// そのフレームの描画入力が借用する動く個体の位置の列を預ける。遊ばない起動では空の列であり、確保も書き込みも起こらない。
    pub(crate) fn 動く個体の大域の位置と向きの指定一覧を預ける(
        &mut self,
    ) -> Vec<動く個体の大域の位置と向きの指定> {
        match self {
            Self::ゲームを遊ばない => Vec::new(),
            Self::キツネの場所巡り(配線) => 配線.台帳を借りる().指定一覧を預ける(),
            Self::歩くだけ(配線) => 配線.台帳を借りる().指定一覧を預ける(),
        }
    }

    pub(crate) fn 動く個体の大域の位置と向きの指定一覧を戻す(
        &mut self, 受け皿: Vec<動く個体の大域の位置と向きの指定>
    ) {
        match self {
            Self::ゲームを遊ばない => {}
            Self::キツネの場所巡り(配線) => 配線.台帳を借りる().指定一覧を戻す(受け皿),
            Self::歩くだけ(配線) => 配線.台帳を借りる().指定一覧を戻す(受け皿),
        }
    }

    /// 描画へ渡す指定の列を、その描画の割合で前と現在の確定値から混ぜ直す。遊ばない起動では混ぜる対象が1件も無い。
    pub(crate) fn 描画へ渡す供給値をこの描画の割合で混ぜ直す(&mut self, 割合: 描画補間の割合) {
        match self {
            Self::ゲームを遊ばない => {}
            Self::キツネの場所巡り(配線) => 配線.台帳を借りる().描画へ渡す指定一覧をこの描画の割合で混ぜ直す(割合),
            Self::歩くだけ(配線) => 配線.台帳を借りる().描画へ渡す指定一覧をこの描画の割合で混ぜ直す(割合),
        }
    }

    /// 刻み境界で確定したプレイヤーの大域位置。遊ばない起動では`None`である。
    /// 混ぜた値でなく確定値を返すのは、この口を読むのがストリーミングの必要チャンク集合の中心だからである。
    /// 常駐するチャンクの集合はゲームが読む高さ場を決めるため、混ぜた値をここへ通すと、描画のためだけに作った値が
    /// 次のゲーム更新の入力へ回り込む(参照: `_doc/設計/時間の規律.md`「判断6」)。
    pub(crate) fn 刻み境界で確定したプレイヤーの大域位置(&self) -> Option<大域ワールド位置> {
        match self {
            Self::ゲームを遊ばない => None,
            Self::キツネの場所巡り(配線) => Some(配線.プレイヤーの大域位置()),
            Self::歩くだけ(配線) => Some(配線.プレイヤーの大域位置()),
        }
    }

    /// カメラの注視点にする、この描画の割合で混ぜた足元の大域位置に目の高さを足した点。遊ばない起動では`None`であり、
    /// カメラは従来どおり起動時の姿勢とマウス操作だけで決まる。描くその個体と同じ混ぜた位置から導くため、
    /// 注視点と個体の位置関係は画面上で動かない。
    pub(crate) fn カメラの注視点にする混ぜた大域位置(&self, 割合: 描画補間の割合) -> Option<大域ワールド位置> {
        match self {
            Self::ゲームを遊ばない => None,
            Self::キツネの場所巡り(配線) => Some(配線.カメラの注視点にする混ぜた大域位置(割合)),
            Self::歩くだけ(配線) => Some(配線.カメラの注視点にする混ぜた大域位置(割合)),
        }
    }

    /// そのフレームにゲームの画面が出す値。遊ばない起動では`None`であり、eguiはゲームの画面を1つも描かない。
    pub(crate) fn 画面へ重ねる表示内容を作る(&self) -> Option<ゲーム画面の表示内容> {
        match self {
            Self::ゲームを遊ばない | Self::歩くだけ(_) => None,
            Self::キツネの場所巡り(配線) => Some(配線.画面へ重ねる表示内容を作る()),
        }
    }
}
