//! エンジンの問い合わせを包んだ世界の形を尋ねる口と、読込済みチャンクの形の出どころの検査。ストリーミングを使わない起動の
//! 選択肢が、地形だけを相手にゲームの語彙の答えを返すことと、出どころが運ぶ形の版が描画の中で動かないことを見る。
//! 読込済みチャンクの形を持つ選択肢の中身はエンジンの問い合わせの検査が固定している。

use blitz_engine::height_field::{高さ場, 高さ場の読み口, 高さ場諸元};
use blitz_engine::{ストリーミングメモリ量, ストリーミング調停, ストリーミング調停設定, チャンク一辺, チャンク目録, チャンク読込設定, 読込済みチャンクの形の版};
use blitz_game::{世界の形を尋ねる口, 掃引が最初に触れる面, 掃引の完全性};
use blitz_math::{メートル, ワールド, 位置, 変位, 大域メートル, 大域ワールド位置};

use super::world_shape_port::{エンジンの問い合わせを包んだ世界の形を尋ねる口, 読込済みチャンクの形の出どころ};

const 平坦な高さ: f32 = 12.5;

fn 平坦な高さ場を持つ読み口() -> 高さ場の読み口 {
    let 諸元 = 高さ場諸元::生成する(大域メートル::生成する(-100.0), 大域メートル::生成する(-100.0), メートル::生成する(100.0), 3, 3).unwrap_or_else(|誤り| panic!("検査用の高さ場の諸元を作れない: {誤り}"));
    let 高さ場 = 高さ場::生成する(諸元, vec![メートル::生成する(平坦な高さ); 9]).unwrap_or_else(|誤り| panic!("検査用の高さ場を作れない: {誤り}"));
    高さ場の読み口::高さ場を持つ世界(高さ場)
}

fn 真下へ3メートル() -> 変位<ワールド> {
    位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(-3.0), メートル::生成する(0.0)).原点からの変位()
}

fn 地表の2メートル上() -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(f64::from(平坦な高さ) + 2.0), 大域メートル::生成する(0.0))
}

#[test]
fn 地形だけの口は地表へ向けた球の掃引に触れると答える() {
    let 読み口 = 平坦な高さ場を持つ読み口();
    let mut 口 = エンジンの問い合わせを包んだ世界の形を尋ねる口::組む(&読み口, 読込済みチャンクの形の出どころ::ストリーミングを使わない起動).unwrap_or_else(|誤り| panic!("地形だけの口を組めない: {誤り}"));
    let 答え = 口
        .掃引した球が最初に触れる面を求める(地表の2メートル上(), メートル::生成する(0.5), 真下へ3メートル())
        .unwrap_or_else(|誤り| panic!("地形だけの口が答えられない: {誤り}"));
    assert_eq!(答え.完全性(), 掃引の完全性::対象範囲を完全に評価できた);
    let 掃引が最初に触れる面::触れる(接触) = 答え.面() else {
        panic!("平坦な地表へ向けた掃引が何にも触れなかった");
    };
    assert!((接触.動けた割合().値() - 0.5).abs() < 1.0e-4, "動けた割合が{}", 接触.動けた割合().値());
    assert!(接触.接触の単位法線().y() > 0.99);
}

/// 反証: 高さ場を持たない世界を評価できない側へ落とすと、地形の無い検収の世界で表示距離が永遠に前の値を保つ。
#[test]
fn 高さ場を持たない世界は何にも触れないを確定した答えとして返す() {
    let 読み口 = 高さ場の読み口::高さ場を持たない世界;
    let mut 口 = エンジンの問い合わせを包んだ世界の形を尋ねる口::組む(&読み口, 読込済みチャンクの形の出どころ::ストリーミングを使わない起動).unwrap_or_else(|誤り| panic!("地形だけの口を組めない: {誤り}"));
    let 答え = 口
        .掃引した球が最初に触れる面を求める(地表の2メートル上(), メートル::生成する(0.5), 真下へ3メートル())
        .unwrap_or_else(|誤り| panic!("地形だけの口が答えられない: {誤り}"));
    assert_eq!(答え.面(), 掃引が最初に触れる面::何にも触れない);
    assert_eq!(答え.完全性(), 掃引の完全性::対象範囲を完全に評価できた);
}

fn 読込済みチャンクを1つも持たない調停を起動する() -> ストリーミング調停 {
    let Ok(一辺) = チャンク一辺::生成する(100.0) else {
        panic!("検査用のチャンク一辺を作れない");
    };
    let 設定 = ストリーミング調停設定 {
        先読み半径: 0,
        上限: ストリーミングメモリ量::生成する(100_000, 100_000),
        読込: チャンク読込設定::既定値(),
    };
    match ストリーミング調停::起動する(設定, チャンク目録::空を作る(一辺)) {
        Ok(調停) => 調停,
        Err(誤り) => panic!("検査用の調停を起動できない: {誤り}"),
    }
}

/// 反証: ストリーミングを使わない起動が版を持たない形にすると、消費側に「版が無い」という分岐が生まれる。
#[test]
fn ストリーミングを使わない起動の版は常に最初の版である() {
    let 出どころ = 読込済みチャンクの形の出どころ::ストリーミングを使わない起動;
    assert_eq!(出どころ.版(), 読込済みチャンクの形の版::最初を作る());
    assert_eq!(出どころ.版(), 読込済みチャンクの形の版::最初を作る());
}

/// 1つの描画の全刻みが同じ版の形を見ることを、出どころが調停の共有借用であることとして固定する。
/// 出どころを保持しているあいだ調停を可変で借りる操作は借用検査が通さないため、保管を変える操作は型の上で書けない。
/// その状態で版を何度読んでも同じ値であることと、保持を落として初めて保管を変えられて版が進むことを対で見る。
#[test]
fn 出どころを保持しているあいだ版は動かず保持を落とすと保管の変更で進む() {
    let mut 調停 = 読込済みチャンクを1つも持たない調停を起動する();
    let 出どころ = 読込済みチャンクの形の出どころ::ストリーミング調停(&調停);
    let 描画の先頭で見た版 = 出どころ.版();
    assert_eq!(出どころ.版(), 描画の先頭で見た版);
    assert_eq!(出どころ.版(), 描画の先頭で見た版);
    // ここで出どころの共有借用が終わる。描画の中では、この行に当たる可変の借用を書けない。
    調停.リセットする();
    assert_eq!(読込済みチャンクの形の出どころ::ストリーミング調停(&調停).版(), 描画の先頭で見た版.次を作る());
}
