//! 読込済みチャンクの形の出どころ: その描画の世界の形を尋ねる口が、建物の形をどこから読むかの枝。
//!
//! `Option`でなく枝で持つのは、ストリーミングを使わない起動が「建物を1棟も持たない世界」という確定した事実であり、
//! 無いことを消費側の分岐へ波及させないためである。フレームの工程がアプリのストリーミング配線から組んでゲーム配線へ渡す。

use blitz_engine::ストリーミング調停;

#[derive(Clone, Copy)]
pub(crate) enum 読込済みチャンクの形の出どころ<'調停> {
    ストリーミングを使わない起動,
    ストリーミング調停(&'調停 ストリーミング調停),
}
