//! エンジンの掃引の答えをゲームロジック層の掃引の答えへ写す純粋な境界。地形の側の答えと、地形と建物を合わせた答えの2つを受ける。
//! 触れた相手が地形か建物かの区別と所在はここで落とす。ゲームの意味付けに要らないためである(判断3)。

use blitz_engine::height_field::{
    掃引したカプセルが最初に触れる地表, 掃引したカプセルが最初に触れる地表の問い合わせ結果
};
use blitz_engine::world_shape_query::{世界の形への問い合わせエラー, 掃引したカプセルが最初に触れる世界の形};
use blitz_engine::{世界問い合わせ結果, 問い合わせ完全性};
use blitz_game::{動けた割合, 掃引が最初に触れる面, 掃引の完全性, 掃引の接触, 掃引の答え};
use blitz_math::{ワールド, 大域ワールド位置, 方向};

use super::error::世界の形を尋ねる口の実装エラー;

pub(super) fn 地表の問い合わせ結果を写す(
    結果: 掃引したカプセルが最初に触れる地表の問い合わせ結果,
) -> Result<掃引の答え, 世界の形を尋ねる口の実装エラー> {
    match 結果 {
        // 地形が1つも無い世界は、地形に触れないという確定した答えを持つ。
        掃引したカプセルが最初に触れる地表の問い合わせ結果::高さ場を持たない世界 => Ok(
            掃引の答え::生成する(掃引が最初に触れる面::何にも触れない, 掃引の完全性::対象範囲を完全に評価できた),
        ),
        掃引したカプセルが最初に触れる地表の問い合わせ結果::カプセルの掃引を評価できない(誤り) => {
            Err(世界の形への問い合わせエラー::from(誤り).into())
        }
        掃引したカプセルが最初に触れる地表の問い合わせ結果::カプセルの掃引を評価した結果(答え) => {
            let 面 = match 答え.値() {
                掃引したカプセルが最初に触れる地表::地表に触れない => 掃引が最初に触れる面::何にも触れない,
                掃引したカプセルが最初に触れる地表::地表に触れる(接触) => {
                    掃引が最初に触れる面::触れる(接触を写す(接触.動けた割合().値(), 接触.接触の大域位置(), 接触.接触の単位法線())?)
                }
            };
            Ok(掃引の答え::生成する(面, 完全性を写す(答え.完全性())))
        }
    }
}

pub(super) fn 世界の形の答えを写す(
    答え: 世界問い合わせ結果<掃引したカプセルが最初に触れる世界の形<'_>>,
) -> Result<掃引の答え, 世界の形を尋ねる口の実装エラー> {
    let 面 = match 答え.値() {
        掃引したカプセルが最初に触れる世界の形::何にも触れない => 掃引が最初に触れる面::何にも触れない,
        掃引したカプセルが最初に触れる世界の形::地形に触れる(接触) => {
            掃引が最初に触れる面::触れる(接触を写す(接触.動けた割合().値(), 接触.接触の大域位置(), 接触.接触の単位法線())?)
        }
        掃引したカプセルが最初に触れる世界の形::建物に触れる(接触) => {
            掃引が最初に触れる面::触れる(接触を写す(接触.動けた割合().値(), 接触.接触の大域位置(), 接触.接触の単位法線())?)
        }
    };
    Ok(掃引の答え::生成する(面, 完全性を写す(答え.完全性())))
}

fn 完全性を写す(完全性: 問い合わせ完全性) -> 掃引の完全性 {
    match 完全性 {
        問い合わせ完全性::対象範囲を完全に評価できた => 掃引の完全性::対象範囲を完全に評価できた,
        問い合わせ完全性::評価できない領域を含む => 掃引の完全性::評価できない領域を含む,
    }
}

// 倍精度の割合を単精度へ狭めるのはゲームロジック層の入口であり、ここはその結果を運ぶだけである。
fn 接触を写す(
    動けた割合: f64,
    接触の大域位置: 大域ワールド位置,
    接触の単位法線: 方向<ワールド>,
) -> Result<掃引の接触, 世界の形を尋ねる口の実装エラー> {
    Ok(掃引の接触::生成する(
        動けた割合::倍精度から生成する(動けた割合)?,
        接触の大域位置,
        接触の単位法線,
    ))
}
