//! 世界の形を尋ねる口の実装が拒む理由。エンジンの問い合わせの失敗と、答えをゲームの語彙へ写せない失敗を束ねる。
//! 到達したら世界の形の契約違反であり、配線は握り潰さず起動エラーとして上へ返す。

use blitz_engine::static_shape::index::静的世界の候補の選別エラー;
use blitz_engine::world_shape_query::世界の形への問い合わせエラー;
use blitz_game::動けた割合エラー;

#[derive(Debug, thiserror::Error)]
pub(crate) enum 世界の形を尋ねる口の実装エラー {
    #[error("読込済みチャンクの形状の候補の選別を組めない: {0}")]
    候補の選別を組めない(#[from] 静的世界の候補の選別エラー),
    #[error("世界の形への問い合わせが失敗した: {0}")]
    問い合わせが失敗した(#[from] 世界の形への問い合わせエラー),
    #[error("世界の形が答えた動けた割合をゲームの語彙へ写せない: {0}")]
    動けた割合を写せない(#[from] 動けた割合エラー),
}
