//! 問い合わせ件数の分布: 刻みごとの移動の観測が持つ問い合わせ件数を、回数・合計・最小・最大として貯め、平均を添えて要約する器。
//! 性能予算(1刻み最大7件)と突き合わせる材料を終了時の報告へ出す。移動を行わなかった刻み(タイトルの裏)も0件として数える。

use blitz_game::問い合わせ件数;

pub(super) struct 問い合わせ件数の分布 {
    回数: u32,
    合計: u64,
    最小: u32,
    最大: u32,
}

// 分布の要約。1度も刻んでいない状態をそのまま枝で持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) enum 問い合わせ件数の要約 {
    まだ刻んでいない,
    刻んだ {
        回数: u32,
        合計: u64,
        最小: u32,
        最大: u32,
        平均: f64,
    },
}

impl 問い合わせ件数の分布 {
    pub(super) fn まだ刻んでいない分布を作る() -> Self {
        Self {
            回数: 0,
            合計: 0,
            最小: u32::MAX,
            最大: 0,
        }
    }

    pub(super) fn 記録する(&mut self, 件数: 問い合わせ件数) {
        self.回数 = self.回数.saturating_add(1);
        self.合計 = self.合計.saturating_add(u64::from(件数.値()));
        self.最小 = self.最小.min(件数.値());
        self.最大 = self.最大.max(件数.値());
    }

    pub(super) fn 要約する(&self) -> 問い合わせ件数の要約 {
        if self.回数 == 0 {
            return 問い合わせ件数の要約::まだ刻んでいない;
        }
        問い合わせ件数の要約::刻んだ {
            回数: self.回数,
            合計: self.合計,
            最小: self.最小,
            最大: self.最大,
            平均: 合計を倍精度へ写す(self.合計) / f64::from(self.回数),
        }
    }
}

// 合計は刻みの回数(u32)×1刻みの件数(性能予算で最大7件)を越えず、倍精度が正確に表す2の53乗の内側にある。
// 数値の`as`を使わずに写すため、u32に収まる値は`From`で、収まらない値は10進の綴りを経て写す。
fn 合計を倍精度へ写す(合計: u64) -> f64 {
    match u32::try_from(合計) {
        Ok(値) => f64::from(値),
        Err(_) => 合計.to_string().parse().unwrap_or(f64::INFINITY),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 最小と最大と平均を要約する() {
        let mut 分布 = 問い合わせ件数の分布::まだ刻んでいない分布を作る();
        let mut 件数 = 問い合わせ件数::零();
        for _ in 0..4 {
            分布.記録する(件数);
            件数 = 件数.一件数える().一件数える();
        }
        assert_eq!(
            分布.要約する(),
            問い合わせ件数の要約::刻んだ {
                回数: 4,
                合計: 12,
                最小: 0,
                最大: 6,
                平均: 3.0,
            }
        );
        assert_eq!(
            問い合わせ件数の分布::まだ刻んでいない分布を作る().要約する(),
            問い合わせ件数の要約::まだ刻んでいない
        );
    }
}
