//! 問い合わせ件数別の刻みの所要時間の分布: 刻みの所要時間の分布(`step_time_distribution`)を、その刻みの問い合わせ件数ごとに
//! 1つずつ持つ器。件数の混じった集団のp50からは1件あたりの費用を導けない(固定費を含む更新時間を件数へ比例配分する根拠が無い)
//! ため、件数ごとの分布を分けて持ち、終了時の報告へ件数別のp50とp99を出す。1件あたりの費用は件数別のp50の差として読む。
//!
//! 件数の器は最初にその件数の刻みを記録したときに作る。件数は性能予算の最大7件までしか現れないため、器は高々8つである。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「性能予算」、`_doc/計測/キャラクターの移動_2026-09-02.md`

use std::collections::BTreeMap;
use std::time::Duration;

use blitz_game::問い合わせ件数;

use super::step_time_distribution::{刻みの所要時間の分布, 刻みの所要時間の要約};

pub(super) struct 問い合わせ件数別の刻みの所要時間の分布 {
    件数ごと: BTreeMap<問い合わせ件数, 刻みの所要時間の分布>,
}

// 1つの件数の刻みだけを集めた分布の要約。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 件数別の刻みの所要時間の要約 {
    pub(crate) 件数: 問い合わせ件数,
    pub(crate) 要約: 刻みの所要時間の要約,
}

impl 問い合わせ件数別の刻みの所要時間の分布 {
    pub(super) fn まだ刻んでいない分布を作る() -> Self {
        Self {
            件数ごと: BTreeMap::new()
        }
    }

    pub(super) fn 記録する(&mut self, 件数: 問い合わせ件数, 所要時間: Duration) {
        self.件数ごと
            .entry(件数)
            .or_insert_with(刻みの所要時間の分布::まだ刻んでいない分布を作る)
            .記録する(所要時間);
    }

    // 件数の昇順に並べた要約。1度も刻んでいなければ空である。
    pub(super) fn 件数の昇順に要約する(&self) -> Vec<件数別の刻みの所要時間の要約> {
        self.件数ごと
            .iter()
            .map(|(件数, 分布)| 件数別の刻みの所要時間の要約 {
                件数: *件数,
                要約: 分布.要約する(),
            })
            .collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 件数ごとに分けた分布を件数の昇順に要約する() {
        let mut 分布 = 問い合わせ件数別の刻みの所要時間の分布::まだ刻んでいない分布を作る();
        let 二件 = 問い合わせ件数::零().一件数える().一件数える();
        for マイクロ秒 in [20_u64, 22, 24] {
            分布.記録する(二件, Duration::from_micros(マイクロ秒));
        }
        分布.記録する(問い合わせ件数::零(), Duration::from_micros(1));
        let 要約 = 分布.件数の昇順に要約する();
        assert_eq!(要約.len(), 2);
        assert_eq!(要約[0].件数, 問い合わせ件数::零());
        assert_eq!(要約[1].件数, 二件);
        let 刻みの所要時間の要約::刻んだ { 回数, 中央値, .. } = 要約[1].要約 else {
            panic!("2件の刻みを3回記録した分布が刻んでいない");
        };
        assert_eq!(回数, 3);
        assert_eq!(中央値, Duration::from_micros(23));
    }

    #[test]
    fn 一度も刻んでいない分布の要約は空である() {
        assert!(
            問い合わせ件数別の刻みの所要時間の分布::まだ刻んでいない分布を作る()
                .件数の昇順に要約する()
                .is_empty()
        );
    }
}
