//! 動く個体を一意に識別する番号。担うのは識別だけであり、その個体がどこに描かれるかも、どこに居るかも持たない。
//! 描画対象を指す添字と別の型にするのは、2つの対応がゲーム状態の台帳の持ち物であり、取り違えを型で止めるためである。
//! 参照: `_doc/計画/ユビキタス言語.md`「エンティティID」。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct エンティティID(u32);

impl エンティティID {
    pub(crate) const fn 生成する(番号: u32) -> Self {
        Self(番号)
    }
}
