//! ゲーム更新の1刻みが何秒ぶんかを答える供給元。担当するのは「そのフレームの刻み秒を1つ答える」ことだけであり、
//! ゲームの状態も進行段階も知らない。
//!
//! 実時間と固定の刻みを型の枝で分けるのは、2つが両立しないためである。読み戻した画像やフレーム数で判定する検収は、
//! 実行ごとに揺れる実時間では成立しない。どちらを使うかは実行の種類が起動時に1度だけ決め、フレームごとの判断は持たない。
//! 経過秒の供給元(`app/time_of_day/exposure_elapsed.rs`)と同じ構造にしてあるのは、同じ形の判断だからである。
//!
//! 注意: 1刻みは描画フレーム1回ぶんであり、累積器を持たない。無期限実行の刻みが実時間で伸び縮みするため、
//! ゲームの動きをアニメーション時刻(固定1/60秒の歩進)と噛み合わせる要求が立った時点で、パターンBへの移行と
//! 累積器を同時に設計する。参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断1」。

use std::time::Instant;

use crate::cli::起動モード;

/// フレーム数の決まった実行が使う刻み。毎秒60フレーム相当であり、アニメーション時刻の固定歩進と同じ値である。
const 検収の固定の刻み秒: f32 = 1.0 / 60.0;
/// 実時間の1フレームに認める上限。デバッガでの停止やウィンドウの移動で実時間が大きく飛んだとき、その1フレームで
/// プレイヤーが目的地を跨いで通り抜けるのを止める。4フレーム毎秒より長い停止は打ち切りとして扱う。
const 実時間の上限秒: f32 = 0.25;

enum 刻みの決め方 {
    /// 無期限実行。前フレームからの実時間を使い、上限で頭打ちにする。最初のフレームは基準が無いため0秒である。
    実フレーム時間 { 前回の実時刻: Option<Instant> },
    /// フレーム数の決まった実行。実時間を1度も読まず、同じ刻みを毎フレーム答える。
    固定の刻み,
}

/// 決め方と、そのフレームぶんの答えを保つ。
pub(super) struct ゲーム更新の刻み秒源 {
    決め方: 刻みの決め方,
    このフレームの刻み秒: f32,
}

impl ゲーム更新の刻み秒源 {
    pub(super) fn 起動モードから決める(モード: 起動モード) -> Self {
        let 決め方 = match モード {
            起動モード::無期限実行 => 刻みの決め方::実フレーム時間 { 前回の実時刻: None },
            起動モード::スモーク実行 { .. } | 起動モード::ベンチ実行 { .. } | 起動モード::段差走査実行 { .. } => {
                刻みの決め方::固定の刻み
            }
        };
        Self {
            決め方,
            このフレームの刻み秒: 0.0,
        }
    }

    /// フレームのゲーム更新で1度だけ呼ぶ。実時間の枝はここでだけ時刻を読む。
    pub(super) fn 進める(&mut self) {
        let 刻みの決め方::実フレーム時間 { 前回の実時刻 } = &mut self.決め方 else {
            self.このフレームの刻み秒 = 検収の固定の刻み秒;
            return;
        };
        let 今 = Instant::now();
        let 経過 = 前回の実時刻.map_or(0.0, |前| 今.duration_since(前).as_secs_f32());
        *前回の実時刻 = Some(今);
        self.このフレームの刻み秒 = 経過.min(実時間の上限秒);
    }

    pub(super) fn このフレームの刻み秒(&self) -> f32 {
        self.このフレームの刻み秒
    }
}
