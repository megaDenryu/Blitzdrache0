//! ゲーム更新の1刻みが何秒ぶんかを答える供給元。担当するのは「1刻みの長さを1つ答える」ことだけであり、
//! ゲームの状態も進行段階も実行の種類も知らない。
//!
//! この値が時間の規律の基本刻みであり、コンポジションルートがここから受け取って時間進行方針へ束ねる。
//! 蓄積器が「1本ぶん貯まった」と数える長さと、ゲームが1刻みで進める長さを別々の数として持たないため、
//! 綴りはこの1箇所だけにある。ゲーム配線はこの値を引数で受け取り、自分では読まない。
//!
//! 注意: 1刻みの長さは実行の種類でも処理速度でも変わらない。変わるのは1回の描画で何本の刻みを進めるかであり、
//! 無期限実行は実時間の蓄積から本数を決め、フレーム数の決まった実行は必ず1本だけ進める。同じ入力系列で
//! 同じ本数を進めた実行は必ず同じ状態で終わる。
//! 参照: `_doc/設計/時間の規律.md`「判断1」「判断2」、`crates/blitz_app/src/app/time_step.rs`。

use blitz_math::秒;

/// 固定刻み1本ぶんの長さ。毎秒60回の更新に相当する。
const 一刻みの秒数: f32 = 1.0 / 60.0;

pub(crate) fn ゲーム更新の一刻みの秒() -> 秒 {
    秒::生成する(一刻みの秒数)
}
