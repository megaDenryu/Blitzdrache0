//! プレイヤーカメラの配線の検査が使う、世界の形を尋ねる口の検査用の実装。掃引の答えを固定で返し、エンジンの問い合わせを1つも要らない。

use blitz_game::{
    世界の形を尋ねる口, 動けた割合, 掃引が最初に触れる面, 掃引の完全性, 掃引の接触, 掃引の答え, 胴体カプセル
};
use blitz_math::{メートル, ワールド, 変位, 大域ワールド位置, 方向};

/// どの掃引にも変位の半分で触れたと答える口。
pub(super) struct 常に半分で触れる口;

impl 世界の形を尋ねる口 for 常に半分で触れる口 {
    type 問い合わせエラー = std::convert::Infallible;

    fn 掃引した胴体が最初に触れる面を求める(
        &mut self,
        胴体: 胴体カプセル,
        掃引の変位: 変位<ワールド>,
    ) -> Result<掃引の答え, Self::問い合わせエラー> {
        self.掃引した球が最初に触れる面を求める(胴体.足元の位置(), 胴体.半径(), 掃引の変位)
    }

    fn 掃引した球が最初に触れる面を求める(
        &mut self,
        中心: 大域ワールド位置,
        _半径: メートル,
        _掃引の変位: 変位<ワールド>,
    ) -> Result<掃引の答え, Self::問い合わせエラー> {
        let 法線 = 方向::生成する(0.0, 0.0, -1.0).unwrap_or_else(|誤り| panic!("検査の法線を作れない: {誤り}"));
        let 割合 = 動けた割合::生成する(0.5).unwrap_or_else(|誤り| panic!("検査の割合を作れない: {誤り}"));
        Ok(掃引の答え::生成する(
            掃引が最初に触れる面::触れる(掃引の接触::生成する(割合, 中心, 法線)),
            掃引の完全性::対象範囲を完全に評価できた,
        ))
    }
}

/// どの掃引にも「何にも触れない」を評価できない領域を含む完全性で答える口。未読込の中を掃引した描画を模す。
pub(super) struct 常に評価できない口;

impl 世界の形を尋ねる口 for 常に評価できない口 {
    type 問い合わせエラー = std::convert::Infallible;

    fn 掃引した胴体が最初に触れる面を求める(
        &mut self,
        胴体: 胴体カプセル,
        掃引の変位: 変位<ワールド>,
    ) -> Result<掃引の答え, Self::問い合わせエラー> {
        self.掃引した球が最初に触れる面を求める(胴体.足元の位置(), 胴体.半径(), 掃引の変位)
    }

    fn 掃引した球が最初に触れる面を求める(
        &mut self,
        _中心: 大域ワールド位置,
        _半径: メートル,
        _掃引の変位: 変位<ワールド>,
    ) -> Result<掃引の答え, Self::問い合わせエラー> {
        Ok(掃引の答え::生成する(
            掃引が最初に触れる面::何にも触れない,
            掃引の完全性::評価できない領域を含む,
        ))
    }
}
