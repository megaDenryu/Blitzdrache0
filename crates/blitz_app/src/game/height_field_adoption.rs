//! 実行時アセット一式の検査段階で高さ場を読み、全検査の成功後にゲーム状態へ据える。

use blitz_engine::height_field::{高さ場の読み口, 高さ場読込エラー};

use super::ゲーム配線;

pub(crate) enum ゲーム用高さ場 {
    遊ばない世界,
    キツネの場所巡り(高さ場の読み口),
    歩くだけ(高さ場の読み口),
}

impl ゲーム配線 {
    pub(crate) fn カタログから高さ場を読み込む(
        &self,
        カタログ: &blitz_engine::カタログ,
    ) -> Result<ゲーム用高さ場, 高さ場読込エラー> {
        match self {
            Self::ゲームを遊ばない => Ok(ゲーム用高さ場::遊ばない世界),
            Self::キツネの場所巡り(_) => Ok(ゲーム用高さ場::キツネの場所巡り(高さ場の読み口::カタログから読み込む(
                カタログ,
            )?)),
            Self::歩くだけ(_) => Ok(ゲーム用高さ場::歩くだけ(高さ場の読み口::カタログから読み込む(カタログ)?)),
        }
    }

    pub(crate) fn 高さ場を据える(&mut self, 高さ場: ゲーム用高さ場) {
        match (self, 高さ場) {
            (Self::ゲームを遊ばない, ゲーム用高さ場::遊ばない世界) => {}
            (Self::キツネの場所巡り(配線), ゲーム用高さ場::キツネの場所巡り(読み口)) => {
                配線.高さ場を据える(読み口)
            }
            (Self::歩くだけ(配線), ゲーム用高さ場::歩くだけ(読み口)) => 配線.高さ場を据える(読み口),
            _ => panic!("高さ場を読み込んだゲームと据えるゲームが一致しなかった"),
        }
    }
}
