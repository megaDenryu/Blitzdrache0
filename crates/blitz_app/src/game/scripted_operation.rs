//! 検収が与える決定的な操作の台本。受け取るのは何回目のゲーム更新かだけであり、返すのはそのフレームの操作入力である。
//! 実時間もウィンドウの入力も読まないため、同じ回数からは必ず同じ操作が出る。
//!
//! 台本を置く理由は、フレーム数の決まった実行が実ウィンドウの操作を1つも通さないことにある(`input/game_intent_policy.rs`)。
//! 通さない実行ではキツネがタイトル表示中のまま1歩も動かず、動く個体の変換がGPUへ届いていることを絵で見る入口が作れない。
//! 検収が自ら与える決定的なカメラ変更(個体詳細段の探査)と同じ位置づけであり、蓄積した入力を経ずに操作を与える。
//!
//! 中身は「タイトルを見せる→決定でプレイへ移る→北へ歩いて1つ目の目的地へ着く→取り消しで終了確認を開く→決定で終わる」である。
//! 段階ごとに更新の回数を区切るのは、検収が`--frames`をこの区切りに合わせて、見たい段階の絵をそのフレームで撮るためである。

use blitz_game::確定済みの操作入力;

use crate::cli::ゲーム操作の出どころ;

/// タイトルを表示したまま何もしない更新の回数。この間の絵がタイトル画面の目視材料になる。
const タイトルを見せる更新の回数: u32 = 30;

/// 決定を押してプレイへ移る更新の回数。
const プレイへ移る更新の回数: u32 = タイトルを見せる更新の回数;

/// 前へ進み続ける最後の更新の回数。1刻み1/60秒・歩く速さ毎秒4メートルであるため、200回で約13.3メートル北へ進む。
/// 1つ目の目的地は真北15メートルにあり、到達とみなす半径3メートルへ入るのは12メートルの地点であるため、
/// 歩き終えたときには到達済みで、まだ目印の柱の手前に立っている。柱を通り過ぎるとカメラと柱の間にキツネが入らず、
/// 目的地付近の絵で柱がキツネを隠す。
const 前へ進む最後の更新の回数: u32 = プレイへ移る更新の回数 + 200;

/// 取り消しを押して終了確認を開く更新の回数。
const 終了確認を開く更新の回数: u32 = 前へ進む最後の更新の回数 + 1;

/// 決定を押して終了を確定する更新の回数。確認を開いてから間を空けるのは、その間の絵が終了確認の目視材料になるためである。
const 終了を決める更新の回数: u32 = 終了確認を開く更新の回数 + 20;

/// そのフレームの操作入力を台本から決める。台本を使わない出どころでは`None`を返し、呼び出し元は実行時の入力を使う。
pub(super) fn 更新回数から台本の操作入力を決める(
    出どころ: ゲーム操作の出どころ,
    ゲーム更新の回数: u32,
) -> Option<確定済みの操作入力> {
    let ゲーム操作の出どころ::決定的な台本 = 出どころ else {
        return None;
    };
    Some(その回数の操作入力を組み立てる(ゲーム更新の回数))
}

fn その回数の操作入力を組み立てる(ゲーム更新の回数: u32) -> 確定済みの操作入力 {
    if ゲーム更新の回数 == プレイへ移る更新の回数 || ゲーム更新の回数 == 終了を決める更新の回数 {
        return 確定済みの操作入力 {
            決定操作を押した瞬間か: true,
            ..確定済みの操作入力::無操作()
        };
    }
    if ゲーム更新の回数 == 終了確認を開く更新の回数 {
        return 確定済みの操作入力 {
            取り消し操作を押した瞬間か: true,
            ..確定済みの操作入力::無操作()
        };
    }
    if (プレイへ移る更新の回数 + 1..=前へ進む最後の更新の回数).contains(&ゲーム更新の回数) {
        return 確定済みの操作入力 {
            前へ進む操作を押しているか: true,
            ..確定済みの操作入力::無操作()
        };
    }
    確定済みの操作入力::無操作()
}
