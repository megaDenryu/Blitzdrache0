//! 検収が与える決定的な操作の台本。受け取るのは何回目のゲーム更新かだけであり、返すのはそのフレームの操作入力である。
//! 実時間もウィンドウの入力も読まないため、同じ回数からは必ず同じ操作が出る。
//!
//! 台本を置く理由は、フレーム数の決まった実行が実ウィンドウの操作を1つも通さないことにある(`input/game_intent_policy.rs`)。
//! 通さない実行ではキツネがタイトル表示中のまま1歩も動かず、動く個体の変換がGPUへ届いていることを絵で見る入口が作れない。
//! 検収が自ら与える決定的なカメラ変更(個体詳細段の探査)と同じ位置づけであり、蓄積した入力を経ずに操作を与える。
//!
//! 中身は「最初の1回で決定を押し、以後は前へ進み続ける」である。決定でタイトルから場所巡りへ移り、そこから北向きに歩き出す。

use blitz_game::確定済みの操作入力;

use crate::cli::ゲーム操作の出どころ;

/// 決定を押す更新の回数。0回目で押すため、1回目の更新から場所巡り中になる。
const 決定を押す更新の回数: u32 = 0;

/// そのフレームの操作入力を台本から決める。台本を使わない出どころでは`None`を返し、呼び出し元は実行時の入力を使う。
pub(super) fn 更新回数から台本の操作入力を決める(
    出どころ: ゲーム操作の出どころ,
    ゲーム更新の回数: u32,
) -> Option<確定済みの操作入力> {
    let ゲーム操作の出どころ::決定的な台本 = 出どころ else {
        return None;
    };
    if ゲーム更新の回数 == 決定を押す更新の回数 {
        return Some(確定済みの操作入力 {
            決定操作を押した瞬間か: true,
            ..確定済みの操作入力::無操作()
        });
    }
    Some(確定済みの操作入力 {
        前へ進む操作を押しているか: true,
        ..確定済みの操作入力::無操作()
    })
}
