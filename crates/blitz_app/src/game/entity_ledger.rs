//! ゲーム状態の台帳。エンティティIDと描画先の対応を持ち、そのフレームの大域位置をレンダラーへ渡す形で保つ。
//! 「動く個体の変換と寿命、およびエンティティIDと描画対象IDの対応」の唯一の所有者である
//! (参照: `_doc/設計/機能配置の指針.md`の所有者表)。
//!
//! 台帳が持つ大域位置は、ゲームの状態が持つ位置を毎フレーム写した供給値である。位置の正本はゲームの状態であり
//! (参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断5」)、台帳が持つのは対応と供給の器である。
//!
//! 指定の列をフィールドとして保つのは、描画入力がこの列を借用で受け取り、毎フレームのヒープ確保を1回も起こさないためである。

use blitz_math::大域ワールド位置;
use blitz_render::frame_input::動く個体の大域位置の指定;
use blitz_render::{動く個体の宣言, 描画束ID};

use super::entity_id::エンティティID;

/// 1体の動く個体が、どの束のどの描画対象のどの個体として描かれるか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 動く個体の描画先 {
    pub(crate) 束id: 描画束ID,
    pub(crate) 描画対象添字: usize,
    pub(crate) 個体添字: u32,
}

pub(crate) struct ゲーム状態の台帳 {
    /// 登録した順のエンティティID。次の列と同じ並びであり、同じ位置が同じ動く個体を指す。
    エンティティid一覧: Vec<エンティティID>,
    /// レンダラーへそのまま渡す指定の列。大域位置だけが毎フレーム書き換わり、件数は登録でしか変わらない。
    指定一覧: Vec<動く個体の大域位置の指定>,
}

impl ゲーム状態の台帳 {
    pub(super) fn 動く個体を1体も持たない台帳を作る() -> Self {
        Self {
            エンティティid一覧: Vec::new(),
            指定一覧: Vec::new(),
        }
    }

    /// 注意: 同じエンティティIDを二重に登録するのは配線の誤りである。2件目の位置の書き込みが1件目にしか届かず、
    /// 2体目が初期位置から動かない絵になる。到達したらバグであるためpanicで止める。
    pub(super) fn 動く個体を登録する(
        &mut self, エンティティid: エンティティID, 描画先: 動く個体の描画先, 初期の大域位置: 大域ワールド位置
    ) {
        assert!(
            !self.エンティティid一覧.contains(&エンティティid),
            "同じエンティティID({エンティティid:?})を二重に登録した"
        );
        self.エンティティid一覧.push(エンティティid);
        self.指定一覧.push(動く個体の大域位置の指定 {
            束id: 描画先.束id,
            描画対象添字: 描画先.描画対象添字,
            個体添字: 描画先.個体添字,
            大域位置: 初期の大域位置,
        });
    }

    /// そのフレームの大域位置を書き込む。登録していないエンティティを指すのは配線の誤りであるためpanicで止める。
    pub(super) fn エンティティの大域位置を書き込む(
        &mut self, エンティティid: エンティティID, 大域位置: 大域ワールド位置
    ) {
        for (登録済み, 指定) in self.エンティティid一覧.iter().zip(self.指定一覧.iter_mut()) {
            if *登録済み == エンティティid {
                指定.大域位置 = 大域位置;
                return;
            }
        }
        panic!("台帳に登録していないエンティティID({エンティティid:?})の大域位置を書き込もうとした");
    }

    /// 束の読込より前にレンダラーへ渡す、その束の動く個体の宣言。読込の1度だけ呼ぶため、ここでの確保は毎フレームに乗らない。
    pub(super) fn 束の動く個体の宣言一覧を作る(&self, 束id: 描画束ID) -> Vec<動く個体の宣言> {
        self.指定一覧
            .iter()
            .filter(|指定| 指定.束id == 束id)
            .map(|指定| 動く個体の宣言 {
                描画対象添字: 指定.描画対象添字,
                個体添字: 指定.個体添字,
            })
            .collect()
    }

    /// 描画入力が借用する指定の列をアプリの外へ預ける。確保した容量を次のフレームへ持ち越すため、描画の成否によらず戻す。
    ///
    /// 注意: 預けている間の台帳は指定の列を1件も持たない。ゲーム更新はフレームの中で描画より前に済んでおり、預けている間に
    /// 大域位置を書き込む経路は無い。書き込むと並びの食い違いとしてpanicで止まる。
    pub(super) fn 指定一覧を預ける(&mut self) -> Vec<動く個体の大域位置の指定> {
        std::mem::take(&mut self.指定一覧)
    }

    pub(super) fn 指定一覧を戻す(&mut self, 受け皿: Vec<動く個体の大域位置の指定>) {
        self.指定一覧 = 受け皿;
    }
}
