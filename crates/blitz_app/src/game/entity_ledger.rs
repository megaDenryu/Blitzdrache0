//! ゲーム状態の台帳。エンティティIDと描画先の対応を持ち、刻みごとに確定した位置と向きを2枚で保つ。
//! 「動く個体の変換と寿命、およびエンティティIDと描画対象IDの対応」の唯一の所有者である
//! (参照: `_doc/設計/機能配置の指針.md`の所有者表)。
//!
//! 台帳が持つ位置と向きは、ゲームの状態が持つ値を刻みごとに写した供給値である。どちらも正本はゲームの状態であり
//! (参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断5」)、台帳が持つのは対応と供給の器である。
//!
//! `エンティティid一覧`と`確定値一覧`と`指定一覧`は同じ並びであり、同じ位置が同じ動く個体を指す。
//! 確定値を2枚で持つのは描画補間のためであり、描画へ渡す指定はこの2枚をその描画の割合で混ぜて作る
//! (参照: `_doc/設計/時間の規律.md`「判断6」)。指定の列をフィールドとして保つのは、描画入力がこの列を
//! 借用で受け取り、毎フレームのヒープ確保を1回も起こさないためである。
//!
//! このファイルが持つのは刻みごとの局面(確定値の繰り上げと据え直し)であり、描画機会ごとの局面(混ぜと預け渡し)は
//! `draw_supply`に、起動時と束の読込時に1度だけ走る登録と宣言は`registration`にある。

mod confirmed_pair;
mod draw_supply;
#[cfg(test)]
mod draw_supply_tests;
mod registration;
mod supply_value;

use blitz_math::大域ワールド位置;
use blitz_render::frame_input::{動く個体の大域の位置と向きの指定, 読込時の向きから天頂軸まわりに回す角};

use confirmed_pair::前と現在の確定値;
pub(crate) use registration::動く個体の描画先;
use supply_value::動く個体の大域の位置と向き;

use super::entity_id::エンティティID;

pub(crate) struct ゲーム状態の台帳 {
    エンティティid一覧: Vec<エンティティID>,         // 登録した順のエンティティID
    確定値一覧: Vec<前と現在の確定値>,               // 刻みごとに繰り上がる前と現在の2枚
    指定一覧: Vec<動く個体の大域の位置と向きの指定>, // その描画で混ぜた値をレンダラーへそのまま渡す列
}

impl ゲーム状態の台帳 {
    pub(super) fn 動く個体を1体も持たない台帳を作る() -> Self {
        Self {
            エンティティid一覧: Vec::new(),
            確定値一覧: Vec::new(),
            指定一覧: Vec::new(),
        }
    }

    /// その刻みで確定した大域の位置と向きを書き込み、直前の確定値を前へ繰り上げる。
    pub(super) fn 刻みで確定した大域の位置と向きを書き込む(
        &mut self,
        エンティティid: エンティティID,
        大域位置: 大域ワールド位置,
        回す角: 読込時の向きから天頂軸まわりに回す角,
    ) {
        let 確定値 = 動く個体の大域の位置と向き::生成する(大域位置, 回す角);
        self.確定値を借りる(エンティティid).刻みの確定値を繰り上げて据える(確定値);
    }

    /// 刻みを経ずに位置を跳ばしたときに、前と現在の2枚とも据え直す。高さ場を据えて世界の中心へ置き直す局面が呼ぶ。
    /// 繰り上げで据えると、跳ぶ前と跳んだ先を混ぜた値が1描画だけ描かれ、個体が跳んだ距離の途中に現れる。
    pub(super) fn 跳ばした大域の位置と向きを前後とも据え直す(
        &mut self,
        エンティティid: エンティティID,
        大域位置: 大域ワールド位置,
        回す角: 読込時の向きから天頂軸まわりに回す角,
    ) {
        let 確定値 = 動く個体の大域の位置と向き::生成する(大域位置, 回す角);
        self.確定値を借りる(エンティティid).どちらも据え直す(確定値);
    }

    /// 登録していないエンティティを指すのは配線の誤りであるためpanicで止める。
    fn 確定値を借りる(&mut self, エンティティid: エンティティID) -> &mut 前と現在の確定値 {
        for (登録済み, 確定値) in self.エンティティid一覧.iter().zip(self.確定値一覧.iter_mut()) {
            if *登録済み == エンティティid {
                return 確定値;
            }
        }
        panic!("エンティティID({エンティティid:?})の大域の位置と向きを書き込めない。台帳に未登録である");
    }
}
