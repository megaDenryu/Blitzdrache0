//! ゲーム状態の台帳。エンティティIDと描画先の対応を持ち、そのフレームの位置と向きをレンダラーへ渡す形で保つ。
//! 「動く個体の変換と寿命、およびエンティティIDと描画対象IDの対応」の唯一の所有者である
//! (参照: `_doc/設計/機能配置の指針.md`の所有者表)。
//!
//! 台帳が持つ位置と向きは、ゲームの状態が持つ値を毎フレーム写した供給値である。どちらも正本はゲームの状態であり
//! (参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断5」)、台帳が持つのは対応と供給の器である。
//!
//! 指定の列をフィールドとして保つのは、描画入力がこの列を借用で受け取り、毎フレームのヒープ確保を1回も起こさないためである。
//!
//! このファイルが持つのは毎フレームの局面(書き込みと預け渡し)であり、起動時と束の読込時に1度だけ走る
//! 登録と宣言は`registration`にある。

mod registration;

use blitz_math::大域ワールド位置;
use blitz_render::frame_input::{動く個体の大域の位置と向きの指定, 読込時の向きから天頂軸まわりに回す角};

pub(crate) use registration::動く個体の描画先;

use super::entity_id::エンティティID;

pub(crate) struct ゲーム状態の台帳 {
    /// 登録した順のエンティティID。次の列と同じ並びであり、同じ位置が同じ動く個体を指す。
    エンティティid一覧: Vec<エンティティID>,
    /// レンダラーへそのまま渡す指定の列。大域位置と回す角だけが毎フレーム書き換わり、件数は登録でしか変わらない。
    指定一覧: Vec<動く個体の大域の位置と向きの指定>,
}

impl ゲーム状態の台帳 {
    pub(super) fn 動く個体を1体も持たない台帳を作る() -> Self {
        Self {
            エンティティid一覧: Vec::new(),
            指定一覧: Vec::new(),
        }
    }

    /// そのフレームの大域位置と向きを書き込む。登録していないエンティティを指すのは配線の誤りであるためpanicで止める。
    pub(super) fn エンティティの大域の位置と向きを書き込む(
        &mut self,
        エンティティid: エンティティID,
        大域位置: 大域ワールド位置,
        回す角: 読込時の向きから天頂軸まわりに回す角,
    ) {
        for (登録済み, 指定) in self.エンティティid一覧.iter().zip(self.指定一覧.iter_mut()) {
            if *登録済み == エンティティid {
                指定.大域位置 = 大域位置;
                指定.読込時の向きから回す角 = 回す角;
                return;
            }
        }
        panic!("エンティティID({エンティティid:?})の大域の位置と向きを書き込めない。台帳に未登録か、指定一覧を描画へ預けている間の書き込みである");
    }

    /// 描画入力が借用する指定の列をアプリの外へ預ける。確保した容量を次のフレームへ持ち越すため、描画の成否によらず戻す。
    ///
    /// 注意: 預けている間の台帳は指定の列を1件も持たない。ゲーム更新はフレームの中で描画より前に済んでおり、預けている間に
    /// 大域位置を書き込む経路は無い。書き込むと並びの食い違いとしてpanicで止まる。
    pub(super) fn 指定一覧を預ける(&mut self) -> Vec<動く個体の大域の位置と向きの指定> {
        std::mem::take(&mut self.指定一覧)
    }

    pub(super) fn 指定一覧を戻す(&mut self, 受け皿: Vec<動く個体の大域の位置と向きの指定>) {
        self.指定一覧 = 受け皿;
    }
}
