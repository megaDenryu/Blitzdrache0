//! キツネの接地と目的地の据え付けに使う高さ場を扱う面。触れるフィールドは`高さ場の読み口`と`状態`と`道順`の3つに限る。
//!
//! 高さ場の問い合わせ結果をゲームロジック層の語彙へ写すのがここの役目である。ゲームロジック層は
//! 高さ場アセットの型を1つも知らず、コンポジションルートのこの写しだけが2つの語彙をつなぐ
//! (参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「第1段階の定義」の項目1)。
//!
//! 目的地の天頂成分をここで置き直すのは、ゲーム側の表が水平の位置しか決めておらず、天頂成分がその場所の
//! 地表高さで決まるためである。置き直さないと、起伏のある地面ではキツネの足元の高さと目的地の高さが
//! 起伏のぶんだけ食い違い、柱の真下に立っても到達が成立しない。

use blitz_engine::height_field::{地表高さの問い合わせ結果, 高さ場の読み口, 高さ場読込エラー};
use blitz_engine::カタログ;
use blitz_game::{場所巡りの道順, 目的地, 足元の地面の高さ};

use super::キツネの場所巡りの配線;

impl キツネの場所巡りの配線 {
    /// カタログから世界の高さ場を据え、目的地の天頂成分をその高さ場の地表へ置き直す。
    /// 呼ばれるのはカタログを構築した起動時の1回だけである。
    /// 高さ場を持たない世界ではキツネの高さも目的地の高さも動かず、既存の検収の世界はこの枝へ落ちる。
    pub(in crate::game) fn カタログから高さ場を据える(&mut self, カタログ: &カタログ) -> Result<(), 高さ場読込エラー> {
        self.高さ場を据える(高さ場の読み口::カタログから読み込む(カタログ)?);
        Ok(())
    }

    /// 読み口を据え、その高さ場に合わせて目的地の天頂成分を置き直す。2つを1つの操作にするのは、
    /// 読み口だけを差し替えて目的地を置き直し忘れると、柱の真下で到達が成立しない状態が黙って作られるためである。
    pub(super) fn 高さ場を据える(&mut self, 読み口: 高さ場の読み口) {
        self.高さ場の読み口 = 読み口;
        self.道順 = self.目的地の天頂成分を地表へ置き直した道順を作る();
    }

    pub(super) fn 足元の地面の高さを求める(&self) -> 足元の地面の高さ {
        match self.高さ場の読み口.大域の水平位置から地表高さを求める(self.状態.プレイヤーの大域位置()) {
            地表高さの問い合わせ結果::高さ場を持たない世界 => 足元の地面の高さ::高さ場を持たない世界,
            地表高さの問い合わせ結果::高さ場の広がりの外 => 足元の地面の高さ::高さ場の広がりの外,
            地表高さの問い合わせ結果::地表高さ(高さ) => 足元の地面の高さ::高さ場から参照した高さ(高さ),
        }
    }

    fn 目的地の天頂成分を地表へ置き直した道順を作る(&self) -> 場所巡りの道順 {
        let 置き直した一覧 = self
            .道順
            .目的地一覧()
            .iter()
            .map(|目的地| self.天頂成分を地表へ置き直した目的地を作る(*目的地))
            .collect();
        場所巡りの道順::生成する(置き直した一覧)
    }

    /// 高さが分からない2つの枝で天頂成分を動かさないのは、表が持つ0メートルへ落とすのと同じ扱いにするためである。
    /// 高さ場を持たない世界ではキツネの天頂成分も動かないため、2つは同じ高さの平面の上に並ぶ。
    fn 天頂成分を地表へ置き直した目的地を作る(&self, 目的地: 目的地) -> 目的地 {
        match self.高さ場の読み口.大域の水平位置から地表高さを求める(目的地.大域位置()) {
            地表高さの問い合わせ結果::高さ場を持たない世界 | 地表高さの問い合わせ結果::高さ場の広がりの外 => {
                目的地
            }
            地表高さの問い合わせ結果::地表高さ(高さ) => 目的地.天頂成分を据えた目的地を返す(高さ),
        }
    }
}
