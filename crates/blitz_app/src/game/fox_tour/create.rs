//! キツネの場所巡りの配線を組み立てる局面。呼ばれるのは起動時の1回だけであり、毎フレームの1刻みの更新とは呼び出し頻度が違う。
//! プレイヤーがどのエンティティで、束のどの描画対象のどの個体として描かれるかをここが決め、ゲーム状態の台帳へ登録する。

use blitz_math::大域ワールド位置;

use super::facing::キツネが読込時に向いている方位角;
use super::キツネの場所巡りの配線;
use crate::cli::{ゲーム操作の出どころ, 起動モード};
use crate::game::entity_id::エンティティID;
use crate::game::fox_player::{プレイヤーのエンティティID, 原点のキツネを登録した台帳を作る};
use crate::input::ゲーム操作の適用方針;

impl キツネの場所巡りの配線 {
    /// 出発地点は世界の原点である。高さ場を持たない世界では天頂成分が動かないため、初期の高さは0に置く。
    /// 出発時の向きを読込時の向きに合わせるのは、遊び始める前のキツネを焼かれた姿勢のまま立たせるためである。
    pub(in crate::game) fn 生成する(モード: 起動モード, 操作の出どころ: ゲーム操作の出どころ) -> Self {
        let 出発地点 = 大域ワールド位置::原点();
        let 出発時の向き = キツネが読込時に向いている方位角();
        let 台帳 = 原点のキツネを登録した台帳を作る();
        Self {
            道順: blitz_game::キツネの場所巡りの道順を作る(),
            状態: blitz_game::場所巡りのゲームの状態::開始時の状態を作る(出発地点, 出発時の向き),
            操作の適用方針: ゲーム操作の適用方針::起動モードから決める(モード),
            操作の出どころ,
            台帳,
            ゲーム更新の回数: 0,
            // 実際の高さ場はカタログを構築した後に据える。カタログの構築は
            // ウィンドウとレンダラーの生成と同じ局面にあり、この組み立ての時点では読めない。据わるまでにフレームは1つも走らない。
            高さ場の読み口: blitz_engine::height_field::高さ場の読み口::高さ場を持たない世界,
        }
    }

    pub(super) fn プレイヤーのエンティティid(&self) -> エンティティID {
        プレイヤーのエンティティID
    }
}
