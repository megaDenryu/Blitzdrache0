//! キツネの場所巡りの配線を組み立てる局面。呼ばれるのは起動時の1回だけであり、毎フレームの1刻みの更新とは呼び出し頻度が違う。
//! プレイヤーがどのエンティティで、束のどの描画対象のどの個体として描かれるかをここが決め、ゲーム状態の台帳へ登録する。

use blitz_math::大域ワールド位置;

use super::キツネの場所巡りの配線;
use crate::app::scene_load::起動時シーンの束ID;
use crate::cli::{ゲーム操作の出どころ, 起動モード};
use crate::game::entity_id::エンティティID;
use crate::game::entity_ledger::{ゲーム状態の台帳, 動く個体の描画先};
use crate::input::ゲーム操作の適用方針;

/// プレイヤーのエンティティID。動く個体が1体だけの1本目では、台帳に載るのはこの1件である。
const プレイヤーのエンティティID: エンティティID = エンティティID::生成する(0);
/// プレイヤーを描く描画対象の、起動時シーンの束の中での並び順。スキニングは束の先頭の描画対象だけへ適用されるため(判断44)、
/// スキン付きのキツネは常にこの位置に来る。
const プレイヤーを描く描画対象添字: usize = 0;
/// キツネの描画対象の個体変換列の中での個体の並び順。スキン付きの描画対象は個体を1体だけ持つ。
const プレイヤーの個体添字: u32 = 0;

impl キツネの場所巡りの配線 {
    /// 出発地点は世界の原点である。高さ場を持たない世界では天頂成分が動かないため、初期の高さは0に置く。
    pub(in crate::game) fn 生成する(モード: 起動モード, 操作の出どころ: ゲーム操作の出どころ) -> Self {
        let 出発地点 = 大域ワールド位置::原点();
        let mut 台帳 = ゲーム状態の台帳::動く個体を1体も持たない台帳を作る();
        台帳.動く個体を登録する(
            プレイヤーのエンティティID,
            動く個体の描画先 {
                束id: 起動時シーンの束ID,
                描画対象添字: プレイヤーを描く描画対象添字,
                個体添字: プレイヤーの個体添字,
            },
            出発地点,
        );
        Self {
            道順: blitz_game::キツネの場所巡りの道順を作る(),
            状態: blitz_game::場所巡りのゲームの状態::開始時の状態を作る(出発地点),
            操作の適用方針: ゲーム操作の適用方針::起動モードから決める(モード),
            操作の出どころ,
            台帳,
            ゲーム更新の回数: 0,
            // 実際の高さ場はカタログを構築した後に据える(`ground`の`カタログから高さ場を据える`)。カタログの構築は
            // ウィンドウとレンダラーの生成と同じ局面にあり、この組み立ての時点では読めない。据わるまでにフレームは1つも走らない。
            高さ場の読み口: blitz_engine::height_field::高さ場の読み口::高さ場を持たない世界,
        }
    }

    pub(super) fn プレイヤーのエンティティid(&self) -> エンティティID {
        プレイヤーのエンティティID
    }
}
