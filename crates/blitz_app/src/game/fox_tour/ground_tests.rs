//! 接地の配線の検査。高さ場を据えた配線でキツネの天頂成分が高さ場の値へ動くこと、
//! 高さ場を持たない配線では出発地点のまま動かないこと、目的地の天頂成分が据えた高さ場の地表へ移ることを見る。
//!
//! 台本の操作で進めるのは、フレーム数の決まった実行が実ウィンドウの操作を1つも通さないためである。

#![allow(clippy::unwrap_used)]

use blitz_engine::height_field::{高さ場, 高さ場の読み口, 高さ場諸元};
use blitz_game::確定済みの操作入力;
use blitz_math::{メートル, ラジアン, 大域メートル};

use super::キツネの場所巡りの配線;
use crate::cli::{ゲーム操作の出どころ, 起動モード};

/// 出発地点(原点)を含む一辺200メートルの平坦な高さ場。全格子点の高さが同じであるため、
/// 双一次補間の結果は歩いた先でもこの値になり、判定が補間の細部に依存しない。
const 平坦な高さ: f32 = 12.5;

fn 平坦な高さ場を作る() -> 高さ場 {
    let 諸元 = 高さ場諸元::生成する(
        大域メートル::生成する(-100.0),
        大域メートル::生成する(-100.0),
        メートル::生成する(100.0),
        3,
        3,
    )
    .unwrap();
    高さ場::生成する(諸元, vec![メートル::生成する(平坦な高さ); 9]).unwrap()
}

fn 台本で進めた配線(読み口: 高さ場の読み口) -> キツネの場所巡りの配線 {
    let mut 配線 = キツネの場所巡りの配線::生成する(起動モード::スモーク実行 { フレーム数: 2 }, ゲーム操作の出どころ::決定的な台本);
    配線.高さ場を据える(読み口);
    for _ in 0..2 {
        配線.一刻み進める(
            確定済みの操作入力::無操作(),
            blitz_game::前へ進む向きの方位角::生成する(ラジアン::生成する(0.0)),
        );
    }
    配線
}

#[test]
fn 高さ場を据えた配線はキツネの天頂成分を高さ場の値へ動かす() {
    let 配線 = 台本で進めた配線(高さ場の読み口::高さ場を持つ世界(平坦な高さ場を作る()));
    assert_eq!(配線.プレイヤーの大域位置().y(), 大域メートル::生成する(f64::from(平坦な高さ)));
}

/// 反証: 目的地が表の天頂成分0メートルのまま残ると、起伏のある地面では柱の真下に立っても到達が成立しない。
#[test]
fn 高さ場を据えると全ての目的地の天頂成分が地表の高さになる() {
    let 配線 = 台本で進めた配線(高さ場の読み口::高さ場を持つ世界(平坦な高さ場を作る()));
    let 目的地一覧 = 配線.道順.目的地一覧();
    assert!(!目的地一覧.is_empty());
    for 目的地 in 目的地一覧 {
        assert_eq!(目的地.大域位置().y(), 大域メートル::生成する(f64::from(平坦な高さ)));
    }
}

/// 反証: 高さ場を持たない世界で天頂成分が動くと、高さ場の無い検収の世界の判定値が変わる。
#[test]
fn 高さ場を持たない配線はキツネの天頂成分を動かさない() {
    let 配線 = 台本で進めた配線(高さ場の読み口::高さ場を持たない世界);
    assert_eq!(配線.プレイヤーの大域位置().y(), 大域メートル::生成する(0.0));
}
