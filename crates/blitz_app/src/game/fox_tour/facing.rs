//! キツネの姿勢の出どころ。担当するのは、この世界のキツネが読込時にどちらを向いて焼かれているかを1つ決めることと、
//! ゲームが持つ世界での向きを、レンダラーが受け取る「読込時の向きからの回転」へ写すことである。
//!
//! 読込時の向きをここが持つのは、それがアセットの性質であってゲームの規則ではないためである。ゲームロジック層は
//! 世界のどちらを向くかだけを決め、絵がどちらを向いて焼かれているかを知らない。レンダラーも世界の方角を知らない。
//! 2つを結ぶ引き算をコンポジションルートのこの1箇所へ置く。

use blitz_game::動く個体が向いている方位角;
use blitz_math::ラジアン;
use blitz_render::frame_input::読込時の向きから天頂軸まわりに回す角;

/// キツネの標準サンプルが読込時に向いている方位角。glTFの慣習でモデルの正面が+Zを向いており、ワールド軸のZが南であるため南を向く。
/// 焼くときに掛けるのは寸法を合わせる一様倍率だけで向きを変えないため、読込時の向きはモデルのままである。
/// 参照: `crates/blitz_asset_compiler/src/runtime_compilation/world/fox_tour_declaration.rs`
const 読込時に向いている方位の度: f32 = 180.0;

/// キツネが読込時に向いている方位角。出発時の姿勢を焼かれた向きに合わせるため、ゲームの開始時の状態にも渡す。
pub(in crate::game) fn キツネが読込時に向いている方位角() -> 動く個体が向いている方位角 {
    動く個体が向いている方位角::生成する(ラジアン::度から(読込時に向いている方位の度))
}

/// 世界での向きを、レンダラーが読込時の姿勢へ掛ける回転角へ写す。
pub(in crate::game) fn 世界での向きを読込時からの回転角へ写す(
    向き: 動く個体が向いている方位角,
) -> 読込時の向きから天頂軸まわりに回す角 {
    読込時の向きから天頂軸まわりに回す角::生成する(
        向き.ラジアンで表した角() - キツネが読込時に向いている方位角().ラジアンで表した角(),
    )
}
