//! ゲーム配線: 世界実行が保持する、どのゲームを回すかの振り分けとゲーム固有の状態。ロジックは書かず、
//! 固定刻みの処理位置ごとの処理の振り分けと、ゲーム固有の状態(進行段階・道順・移動状態)を読む口だけを持つ。
//! 2つのゲームが共有する状態(台帳・高さ場の読み口・カメラ・移動の記録・操作の適用の方式)は世界実行が所有し、
//! 各処理位置の処理は自分が触るものだけを名前の付いた引数で受ける。台帳はどの処理位置の引数にも入らない。台帳へ書くのは世界実行の
//! 刻みの確定の処理位置と高さ場の据え付けであり、ゲーム配線は`刻み境界で確定したプレイヤー`(台帳へ写す材料の1組)を答えるだけである(判断13)。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断12」。
//!
//! 遊ばない状態を`Option`でなく選択肢で持つのは、`--game`の指定が無い起動でゲーム更新も操作の確定も1つも走らないことを
//! 型で保つためである。既存の入口(スモーク・ベンチ・段差走査・報告)はどれもこの選択肢へ落ちる。
//! 固定刻みの処理位置ごとの処理は`tick`に、処理位置をまたいで運ぶ決定は`tick_decision`に、ゲーム固有の状態を読む口は`supply`に、
//! 高さ場の地表への置き直しは`ground`にある。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断12」「判断13」。

