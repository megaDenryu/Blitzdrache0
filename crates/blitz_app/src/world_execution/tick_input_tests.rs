//! 刻み入力が、配る器から受け取ったヨーを保持し、生成の後にカメラが動いても読み直さないことと、器が全ての刻みへ同じヨーを
//! 配ることの検証。この検査が固定するのはその保持だけであり、生産コードの工程の並び(`app/frame.rs`が刻みをカメラの更新より
//! 前に回すこと、`app/frame/game_steps.rs`が入力の確定でヨーを1度読むこと)は固定しない。工程の並びは型も検査も守っていない。
//! あわせて、刻み入力が描画補間の割合も混ぜた注視点も1つも持たないため、描画の値は固定刻みへ戻らない。
//! 実画面もレンダラーも使わず、エンジンのカメラと刻み入力だけで組む。
//! 参照: `_doc/設計/時間の規律.md`「判断6」「入力の規律」、`_doc/設計/ゲーム制作アーキテクチャ.md`「判断12」。

use blitz_engine::{カメラ, カメラの操作意図};
use blitz_game::{前へ進む向きの方位角, 確定済みの操作入力};
use blitz_math::ラジアン;

use super::contract::{刻み入力, 読込済みチャンクの形の出どころ};
use crate::app::固定刻みの番号;
use crate::input::刻みごとの操作入力;

fn ヨーを載せた器(ヨー: ラジアン) -> 刻みごとの操作入力 {
    刻みごとの操作入力::一描画の確定から生成する(確定済みの操作入力::無操作(), ヨー)
}

/// ヨーを10度回すカメラの操作意図。その描画のマウス操作を模す。
fn ヨーを回す意図() -> カメラの操作意図 {
    カメラの操作意図 {
        ヨー差分: ラジアン::度から(10.0),
        ピッチ差分: ラジアン::生成する(0.0),
        距離倍率: 1.0,
    }
}

/// 反証: 刻み入力がヨーを保持せずカメラを参照で持つと、生成の後のカメラ操作がその刻みの向きへ回り込む。
#[test]
fn 刻み入力は生成の後にカメラが動いても生成時のヨーから作った向きを保つ() {
    let mut カメラ = カメラ::生成する();
    let 生成時のヨー = カメラ.ヨー();
    let mut 器 = ヨーを載せた器(生成時のヨー);
    let 入力 = 刻み入力::配る器から次の刻みぶんを生成する(&mut 器, 読込済みチャンクの形の出どころ::ストリーミングを使わない起動, 固定刻みの番号::起動時の最初());
    カメラ.更新する(ヨーを回す意図());
    assert_ne!(カメラ.ヨー(), 生成時のヨー, "検査の前提: カメラの操作でヨーが動く");
    assert_eq!(入力.前へ進む向きの方位角(), 前へ進む向きの方位角::生成する(生成時のヨー));
    assert_ne!(入力.前へ進む向きの方位角(), 前へ進む向きの方位角::生成する(カメラ.ヨー()));
}

/// 反証: 器がヨーを最初の刻みだけへ配ると、刻みが4本進んだ描画の2本目以降が前へ進む向きを失う。
#[test]
fn 器から生成した全ての刻みの前へ進む向きの方位角は同じヨーを写す() {
    let ヨー = ラジアン::度から(30.0);
    let mut 器 = ヨーを載せた器(ヨー);
    let mut 番号 = 固定刻みの番号::起動時の最初();
    for _ in 0..4 {
        let 入力 = 刻み入力::配る器から次の刻みぶんを生成する(&mut 器, 読込済みチャンクの形の出どころ::ストリーミングを使わない起動, 番号);
        assert_eq!(入力.前へ進む向きの方位角(), 前へ進む向きの方位角::生成する(ヨー));
        assert_eq!(入力.固定刻みの番号(), 番号);
        番号 = 番号.本数だけ後の番号(1);
    }
}
