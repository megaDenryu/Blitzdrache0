//! 刻み入力の前へ進む向きの方位角が、その描画のカメラ操作を反映する前に読んだヨーから作られることの検証。
//! 描画の途中でカメラのヨーが変わっても、その描画の刻みが読む向きは操作前の値であり、
//! 刻み入力は描画補間の割合も混ぜた注視点も1つも持たないため、描画の値は固定刻みへ戻らない。
//! 実画面もレンダラーも使わず、エンジンのカメラと世界実行だけで組む。
//! 参照: `_doc/設計/時間の規律.md`「判断6」「入力の規律」、`_doc/設計/ゲーム制作アーキテクチャ.md`「判断12」。

use blitz_engine::{カメラ, カメラの操作意図};
use blitz_game::{前へ進む向きの方位角, 確定済みの操作入力};
use blitz_math::ラジアン;

use super::contract::{刻み入力, 読込済みチャンクの形の出どころ};

/// ヨーを10度回すカメラの操作意図。その描画のマウス操作を模す。
fn ヨーを回す意図() -> カメラの操作意図 {
    カメラの操作意図 {
        ヨー差分: ラジアン::度から(10.0),
        ピッチ差分: ラジアン::生成する(0.0),
        距離倍率: 1.0,
    }
}

/// 反証: ヨーをカメラの更新の後に読むと、その描画のマウス操作が同じ描画の刻みの向きへ回り込み、
/// 描画機会の時間意味の値が固定刻みの入力になる。
#[test]
fn この描画の刻みが読む前へ進む向きはカメラ操作を反映する前のヨーから作られる() {
    let mut カメラ = カメラ::生成する();
    let 操作前のヨー = カメラ.ヨー();
    let 入力 = 刻み入力::カメラのヨーから生成する(確定済みの操作入力::無操作(), 操作前のヨー, 読込済みチャンクの形の出どころ::ストリーミングを使わない起動);
    カメラ.更新する(ヨーを回す意図());
    assert_ne!(カメラ.ヨー(), 操作前のヨー, "検査の前提: カメラの操作でヨーが動く");
    assert_eq!(入力.前へ進む向きの方位角(), 前へ進む向きの方位角::生成する(操作前のヨー));
    assert_ne!(入力.前へ進む向きの方位角(), 前へ進む向きの方位角::生成する(カメラ.ヨー()));
}

#[test]
fn 前へ進む向きの方位角はヨーをそのまま写す() {
    let ヨー = ラジアン::度から(30.0);
    let 入力 = 刻み入力::カメラのヨーから生成する(確定済みの操作入力::無操作(), ヨー, 読込済みチャンクの形の出どころ::ストリーミングを使わない起動);
    assert_eq!(入力.前へ進む向きの方位角(), 前へ進む向きの方位角::生成する(ヨー));
}
