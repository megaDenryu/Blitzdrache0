//! 高さ場の問い合わせ結果をゲームロジック層の足元の高さへ写す純粋な境界。

use blitz_engine::height_field::地表高さの問い合わせ結果;
use blitz_game::足元の地面の高さ;

pub(super) fn 足元の地面の高さへ写す(結果: 地表高さの問い合わせ結果) -> 足元の地面の高さ {
    match 結果 {
        地表高さの問い合わせ結果::高さ場を持たない世界 => 足元の地面の高さ::高さ場を持たない世界,
        地表高さの問い合わせ結果::高さ場の広がりの外 => 足元の地面の高さ::高さ場の広がりの外,
        地表高さの問い合わせ結果::地表高さ(高さ) => 足元の地面の高さ::高さ場から参照した高さ(高さ),
    }
}
