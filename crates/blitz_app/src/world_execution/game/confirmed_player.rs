//! 刻み境界で確定したプレイヤー。ゲーム配線が刻みの確定の処理位置と高さ場の据え付けへ答える、台帳へ写す材料の1組である。
//! 持つのはエンティティIDと大域位置と、読込時の向きからの回転角へ写した向きであり、3つを1つの値にするのは、
//! 遊ばない起動で3つが同時に無く、遊ぶ起動で3つが同時に在るためである。別々の`Option`で持つと「一部だけ在る」という
//! 起こり得ない組み合わせが型の上で表現でき、読む側がその不整合を毎回考えることになる。
//!
//! 世界での向きを読込時からの回転角へ写すのをこの値の生成で行うのは、写しがキツネのアセットの性質(`fox_tour::facing`)であり、
//! 台帳も世界実行もそれを知らないためである。台帳が受け取るのは写した後の角だけである。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」。

use blitz_game::プレイヤーの位置と向き;
use blitz_math::大域ワールド位置;
use blitz_render::frame_input::読込時の向きから天頂軸まわりに回す角;

use super::fox_tour::facing::世界での向きを読込時からの回転角へ写す;
use crate::world_execution::entity_id::エンティティID;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::world_execution) struct 刻み境界で確定したプレイヤー {
    エンティティid: エンティティID,
    大域位置: 大域ワールド位置,
    読込時の向きから回す角: 読込時の向きから天頂軸まわりに回す角,
}

impl 刻み境界で確定したプレイヤー {
    /// ゲームの状態が持つ位置と向きから、台帳へ写す材料を作る。向きはここで読込時からの回転角へ写す。
    pub(super) fn ゲームの位置と向きから写す(エンティティid: エンティティID, 位置と向き: プレイヤーの位置と向き) -> Self {
        Self {
            エンティティid,
            大域位置: 位置と向き.大域位置(),
            読込時の向きから回す角: 世界での向きを読込時からの回転角へ写す(位置と向き.向き()),
        }
    }

    pub(in crate::world_execution) fn エンティティid(self) -> エンティティID {
        self.エンティティid
    }

    pub(in crate::world_execution) fn 大域位置(self) -> 大域ワールド位置 {
        self.大域位置
    }

    pub(in crate::world_execution) fn 読込時の向きから回す角(self) -> 読込時の向きから天頂軸まわりに回す角 {
        self.読込時の向きから回す角
    }
}
