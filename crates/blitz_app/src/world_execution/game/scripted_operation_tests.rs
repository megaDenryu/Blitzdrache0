//! 台本の各段階が当たる刻みが、判断13より前の「ゲーム更新の回数」と1つもずれないことの検証。
//! 回数は0から始まり刻みの後に増えていたため、番号0の刻みがタイトル、30番目の刻みが決定、31番目から230番目が前へ進む、
//! 231番目が取り消し、251番目が決定である。区切りは定数を参照して読み、値を書き写さない。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」。

use blitz_game::確定済みの操作入力;

use super::scripted_operation::{その番号の刻みの操作入力を組み立てる, プレイへ移る刻みの番号, 前へ進む最後の刻みの番号, 終了を決める刻みの番号, 終了確認を開く刻みの番号};
use crate::app::固定刻みの番号;

#[test]
fn 番号0の刻みから決定の直前まではタイトルを見せて何も押さない() {
    let mut 番号 = 固定刻みの番号::起動時の最初();
    while 番号 < プレイへ移る刻みの番号 {
        assert_eq!(その番号の刻みの操作入力を組み立てる(番号), 確定済みの操作入力::無操作(), "番号{番号}");
        番号 = 番号.本数だけ後の番号(1);
    }
}

#[test]
fn 区切りの番号の刻みで決定と取り消しを押す() {
    assert!(その番号の刻みの操作入力を組み立てる(プレイへ移る刻みの番号).決定操作を押した瞬間か);
    assert!(その番号の刻みの操作入力を組み立てる(終了確認を開く刻みの番号).取り消し操作を押した瞬間か);
    assert!(その番号の刻みの操作入力を組み立てる(終了を決める刻みの番号).決定操作を押した瞬間か);
    assert_eq!(プレイへ移る刻みの番号, 固定刻みの番号::起動時の最初().本数だけ後の番号(30));
    assert_eq!(終了を決める刻みの番号, 固定刻みの番号::起動時の最初().本数だけ後の番号(251));
}

#[test]
fn 決定の次の刻みから前へ進む最後の刻みまで前へ進み続ける() {
    let 最初 = プレイへ移る刻みの番号.本数だけ後の番号(1);
    assert!(その番号の刻みの操作入力を組み立てる(最初).前へ進む操作を押しているか);
    assert!(その番号の刻みの操作入力を組み立てる(前へ進む最後の刻みの番号).前へ進む操作を押しているか);
    assert!(!その番号の刻みの操作入力を組み立てる(プレイへ移る刻みの番号).前へ進む操作を押しているか);
    assert!(!その番号の刻みの操作入力を組み立てる(前へ進む最後の刻みの番号.本数だけ後の番号(1)).前へ進む操作を押しているか);
}
