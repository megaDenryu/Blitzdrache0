//! この刻みで規則が行うこと: 固定刻みの工程が段のあいだで運ぶ、この刻みの規則の進みを表す状態機械。操作入力の適用と操作で決まる状態遷移の段が
//! 写した操作の意図を載せ、意図の生成とこの刻みで規則が行うことの決定の段がそれを受けて移動と到達判定を行うか行わないかへ進め、移動と作用の要求の段と
//! 世界の結果で決まる状態遷移の段がその決定に従う。不変条件「メニューの裏で位置が動かず到達しない」の判定は意図の生成とこの刻みで規則が行うことの決定の段の1箇所であり、
//! 後続の段は場所巡り中かを自分で判定せずこの決定を読む。
//! 段の並びが壊れると(意図の生成とこの刻みで規則が行うことの決定が操作入力の適用と操作で決まる状態遷移より前、移動が意図の生成とこの刻みで規則が行うことの決定より前)、段は前の段が進めていない値を受ける。
//! それは工程のバグであるため、読む口は到達したら止める。`Option`や無操作の意図で初期化しないのは、「まだ写していない」や
//! 「まだ決まっていない」を値の不在や偶然の値に密輸すると、段の順序の誤りが黙って通るためである。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」。

use blitz_game::{ゲームの操作意図, 一刻みの移動の入力};

pub(in crate::world_execution) enum この刻みで規則が行うこと {
    まだ決まっていない,                       // 段の並びの先頭から操作入力の適用と操作で決まる状態遷移の段までの値
    操作の意図を写した(ゲームの操作意図),     // 操作入力の適用と操作で決まる状態遷移の段が写した意図。意図の生成とこの刻みで規則が行うことの決定の段がこれを読んで次の2枝のどちらかへ進める
    移動と到達判定を行う(一刻みの移動の入力), // 場所巡り中の刻み。歩くだけは進行段階を持たず常にこの枝
    移動も到達判定も行わない,                 // タイトル表示中・終了確認中・終了決定済みの刻みと、遊ばない起動
}

impl この刻みで規則が行うこと {
    /// 操作入力の適用と操作で決まる状態遷移の段が写した操作の意図を返す。意図の生成とこの刻みで規則が行うことの決定の段だけが読む。写した意図を持たない値を読んだら、
    /// 段の並びで操作入力の適用と操作で決まる状態遷移の段が意図の生成とこの刻みで規則が行うことの決定の段より前に1度だけ無いという不変条件の破れであり、止める。
    pub(in crate::world_execution) fn 写した操作の意図を返す(&self) -> ゲームの操作意図 {
        match self {
            Self::操作の意図を写した(意図) => *意図,
            Self::まだ決まっていない | Self::移動と到達判定を行う(_) | Self::移動も到達判定も行わない => {
                panic!("この刻みの操作の意図がまだ写されていない(固定刻みの段の並びで、操作入力の適用と操作で決まる状態遷移の段が意図の生成とこの刻みで規則が行うことの決定の段より前に1度だけ無い)")
            }
        }
    }

    /// 移動と到達判定を行う刻みなら移動の入力を返し、行わない刻みなら`None`を返す。
    /// 決まっていない値を読んだら、段の並びで意図の生成とこの刻みで規則が行うことの決定の段が移動より前に無いという不変条件の破れであり、止める。
    pub(in crate::world_execution) fn 移動と到達判定を行うなら移動の入力を返す(&self) -> Option<&一刻みの移動の入力> {
        match self {
            Self::まだ決まっていない | Self::操作の意図を写した(_) => {
                panic!("この刻みで規則が行うことがまだ決まっていない(固定刻みの段の並びで、意図の生成とこの刻みで規則が行うことの決定の段が移動と作用の要求の段と世界の結果で決まる状態遷移の段より前に無い)")
            }
            Self::移動と到達判定を行う(移動の入力) => Some(移動の入力),
            Self::移動も到達判定も行わない => None,
        }
    }
}
