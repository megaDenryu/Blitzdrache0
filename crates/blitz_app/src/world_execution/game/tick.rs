//! ゲーム配線の固定刻み1本ぶんの更新の振り分け。呼ばれるのは世界実行の固定刻みの入口からであり、
//! 触れるのは遊ぶゲームの選択肢の配線と、借りて渡された共有の状態だけである。
//! 刻みの中でゲームの終了が決まったら刻み結果でそれを返し、世界実行はゲームの内部を覗かない。

use blitz_math::秒;

use super::{ゲーム配線, 一刻みが借りる共有の状態};
use crate::world_execution::contract::{世界の形を尋ねる口の実装エラー, 刻み入力, 刻み結果};

impl ゲーム配線 {
    pub(in crate::world_execution) fn 一刻み進める(&mut self, 入力: 刻み入力<'_>, 一刻みの秒: 秒, 共有: 一刻みが借りる共有の状態<'_>) -> Result<刻み結果, 世界の形を尋ねる口の実装エラー> {
        match self {
            Self::ゲームを遊ばない => {}
            Self::キツネの場所巡り(配線) => {
                配線.一刻み進める(入力, 一刻みの秒, 共有)?;
                if 配線.終了が決まったか() {
                    return Ok(刻み結果::終了する);
                }
            }
            Self::歩くだけ(配線) => 配線.一刻み進める(入力, 一刻みの秒, 共有)?,
        }
        Ok(刻み結果::続ける)
    }
}
