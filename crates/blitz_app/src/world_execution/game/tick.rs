//! ゲーム配線の固定刻みの段ごとの処理の振り分け。呼ばれるのは世界実行の固定刻みの入口の各段からであり、
//! 段ごとに1つの口を持つ。操作入力の適用と操作で決まる状態遷移の段は確定済みの操作入力を意図へ写して進行段階を遷移させ、意図の生成とこの刻みで規則が行うことの決定の段は
//! `この刻みで規則が行うこと`を決め、移動と作用の要求の段と世界の結果で決まる状態遷移の段はその決定に従う。
//! 各口は自分が触る共有の状態だけを名前の付いた引数で受け、世界実行を丸ごと受けない(切り出しの根拠義務)。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」。

use blitz_engine::height_field::高さ場の読み口;
use blitz_game::{ゲームの操作意図, 一刻みの移動の入力, 移動の観測};
use blitz_math::秒;

use super::{この刻みで規則が行うこと, ゲーム配線};
use crate::input::ゲーム操作の適用の方式;
use crate::world_execution::contract::{世界の形を尋ねる口の実装エラー, 刻み入力};
use crate::world_execution::movement_record::移動の観測の記録;

impl ゲーム配線 {
    /// 操作入力の適用と操作で決まる状態遷移の段。確定済みの操作入力をゲームの操作意図へ写して返し、進行段階を遷移させる(門)。
    /// 写した意図は決定へ載せて意図の生成とこの刻みで規則が行うことの決定の段へ運び、配線は持ち越さない。台本の操作を使うかはキツネの場所巡りの配線が
    /// 自分の操作の出どころで決める。遊ばない起動は操作を1つも受けないため無操作を返す(この段は遊ばない起動では呼ばれない)。
    pub(in crate::world_execution) fn 操作入力を適用して進行段階を遷移させる(&mut self, 入力: &刻み入力<'_>, 操作の適用の方式: ゲーム操作の適用の方式) -> ゲームの操作意図 {
        match self {
            Self::ゲームを遊ばない => ゲームの操作意図::無操作(),
            Self::キツネの場所巡り(配線) => 配線.操作入力を適用して進行段階を遷移させる(入力, 操作の適用の方式),
            Self::歩くだけ(_) => 操作の適用の方式.通す(ゲームの操作意図::確定済みの操作入力から写す(入力.操作入力())),
        }
    }

    /// 意図の生成とこの刻みで規則が行うことの決定の段。写した操作の意図と遷移後の進行段階から、この刻みで規則が行うことを決める。
    pub(in crate::world_execution) fn この刻みで規則が行うことを決める(&self, 意図: ゲームの操作意図, 入力: &刻み入力<'_>, 一刻みの秒: 秒) -> この刻みで規則が行うこと {
        let 移動の入力 = 一刻みの移動の入力 {
            意図,
            刻み: 一刻みの秒,
            前へ進む向き: 入力.前へ進む向きの方位角(),
        };
        match self {
            Self::ゲームを遊ばない => この刻みで規則が行うこと::移動も到達判定も行わない,
            Self::キツネの場所巡り(配線) => 配線.この刻みで規則が行うことを決める(移動の入力),
            Self::歩くだけ(_) => この刻みで規則が行うこと::移動と到達判定を行う(移動の入力),
        }
    }

    /// 移動と作用の要求の段。決定が「行う」なら掃引でプレイヤーを一刻み動かす。行わない刻みでも観測を1件記録するのは、
    /// 移動の観測の記録が「観測を記録してから所要時間を記録する」を不変条件に持つためである。
    pub(in crate::world_execution) fn プレイヤーを一刻み動かす(
        &mut self,
        決定: &この刻みで規則が行うこと,
        入力: &刻み入力<'_>,
        高さ場の読み口: &高さ場の読み口,
        移動の記録: &mut 移動の観測の記録,
    ) -> Result<(), 世界の形を尋ねる口の実装エラー> {
        let Some(移動の入力) = 決定.移動と到達判定を行うなら移動の入力を返す() else {
            移動の記録.刻みの観測を記録する(移動の観測::移動を行わなかった刻み());
            return Ok(());
        };
        match self {
            Self::ゲームを遊ばない => {}
            Self::キツネの場所巡り(配線) => 配線.プレイヤーを一刻み動かす(移動の入力, 高さ場の読み口, 入力.出どころ(), 移動の記録)?,
            Self::歩くだけ(配線) => 配線.プレイヤーを一刻み動かす(移動の入力, 高さ場の読み口, 入力.出どころ(), 移動の記録)?,
        }
        Ok(())
    }

    /// 世界の結果で決まる状態遷移の段。決定が「行う」なら目的地への到達を判定して場所巡りの進行を進める。歩くだけは目的地を持たない。
    pub(in crate::world_execution) fn 目的地への到達を判定して場所巡りの進行を進める(&mut self, 決定: &この刻みで規則が行うこと) {
        if 決定.移動と到達判定を行うなら移動の入力を返す().is_none() {
            return;
        }
        match self {
            Self::ゲームを遊ばない | Self::歩くだけ(_) => {}
            Self::キツネの場所巡り(配線) => 配線.目的地への到達を判定して場所巡りの進行を進める(),
        }
    }
}
