//! 検収が与える決定的な操作の台本。受け取るのはその刻みの固定刻みの番号だけであり、返すのはその刻みの操作入力である。
//! 実時間もウィンドウの入力も読まないため、同じ番号からは必ず同じ操作が出る。
//!
//! 台本を置く理由は、フレーム数の決まった実行が実ウィンドウの操作を1つも通さないことにある(`input/game_intent_policy.rs`)。
//! 通さない実行ではキツネがタイトル表示中のまま1歩も動かず、動く個体の変換がGPUへ届いていることを絵で見る入口が作れない。
//! 検収が自ら与える決定的なカメラ変更(個体詳細段の探査)と同じ位置づけであり、蓄積した入力を経ずに操作を与える。
//!
//! 中身は「タイトルを見せる→決定でプレイへ移る→北へ歩いて1つ目の目的地へ着く→取り消しで終了確認を開く→決定で終わる」である。
//! 段階ごとに刻みの番号を区切るのは、検収が`--frames`をこの区切りに合わせて、見たい段階の絵をそのフレームで撮るためである。
//! 番号は最初の刻みが0であり、判断13より前にこの配線が数えていた「ゲーム更新の回数」(0から始まり刻みの後に増える)と
//! 同じ刻みに同じ値が当たる。区切りの値は変えていない(参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」)。

use blitz_game::確定済みの操作入力;

use crate::app::固定刻みの番号;
use crate::cli::ゲーム操作の出どころ;

/// タイトルを表示したまま何もしない刻みの本数。この間の絵がタイトル画面の目視材料になる。
const タイトルを見せる刻みの本数: u64 = 30;

/// 決定を押してプレイへ移る刻みの番号。
pub(super) const プレイへ移る刻みの番号: 固定刻みの番号 = 固定刻みの番号::起動時の最初().本数だけ後の番号(タイトルを見せる刻みの本数);

/// 前へ進み続ける最後の刻みの番号。1刻み1/60秒・歩く速さ毎秒4メートルであるため、200刻みで約13.3メートル北へ進む。
/// 1つ目の目的地は真北15メートルにあり、到達とみなす半径3メートルへ入るのは12メートルの地点であるため、
/// 歩き終えたときには到達済みで、まだ目印の柱の手前に立っている。柱を通り過ぎるとカメラと柱の間にキツネが入らず、
/// 目的地付近の絵で柱がキツネを隠す。
pub(super) const 前へ進む最後の刻みの番号: 固定刻みの番号 = プレイへ移る刻みの番号.本数だけ後の番号(200);

/// 取り消しを押して終了確認を開く刻みの番号。
pub(super) const 終了確認を開く刻みの番号: 固定刻みの番号 = 前へ進む最後の刻みの番号.本数だけ後の番号(1);

/// 決定を押して終了を確定する刻みの番号。確認を開いてから間を空けるのは、その間の絵が終了確認の目視材料になるためである。
pub(in crate::world_execution) const 終了を決める刻みの番号: 固定刻みの番号 = 終了確認を開く刻みの番号.本数だけ後の番号(20);

/// その刻みの操作入力を台本から決める。台本を使わない出どころでは`None`を返し、呼び出し元は実行時の入力を使う。
pub(super) fn 更新回数から台本の操作入力を決める(出どころ: ゲーム操作の出どころ, 番号: 固定刻みの番号) -> Option<確定済みの操作入力> {
    let ゲーム操作の出どころ::決定的な台本 = 出どころ else {
        return None;
    };
    Some(その番号の刻みの操作入力を組み立てる(番号))
}

pub(super) fn その番号の刻みの操作入力を組み立てる(番号: 固定刻みの番号) -> 確定済みの操作入力 {
    if 番号 == プレイへ移る刻みの番号 || 番号 == 終了を決める刻みの番号 {
        return 確定済みの操作入力 {
            決定操作を押した瞬間か: true,
            ..確定済みの操作入力::無操作()
        };
    }
    if 番号 == 終了確認を開く刻みの番号 {
        return 確定済みの操作入力 {
            取り消し操作を押した瞬間か: true,
            ..確定済みの操作入力::無操作()
        };
    }
    if (プレイへ移る刻みの番号.本数だけ後の番号(1)..=前へ進む最後の刻みの番号).contains(&番号) {
        return 確定済みの操作入力 {
            前へ進む操作を押しているか: true,
            ..確定済みの操作入力::無操作()
        };
    }
    確定済みの操作入力::無操作()
}
