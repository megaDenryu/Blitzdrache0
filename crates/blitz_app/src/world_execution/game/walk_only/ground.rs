//! 歩くだけの配線が、据える高さ場の地表へ足元を置き直す面。触れるフィールドは`状態`に限り、読み口は世界実行から借りる。
//! 置き直した位置と向きを台帳へ写すのは世界実行の高さ場の据え付けであり、ここは台帳へ書かない(判断13)。
//!
//! 高さ場の点参照で足元を地表へ置くのは、高さ場を据えるこの据え直しの1箇所だけである。毎刻みの接地は掃引による
//! 接地判定が決める(`_doc/設計/キャラクターの移動とカメラ.md`「判断5」)。据え直しを残すのは、世界の中心へ置き直した
//! 直後の足元が地表より下にあると、胴体が地面の中から始まって掃引が一歩も動けないためである。

use blitz_engine::height_field::高さ場の読み口;
use blitz_game::{歩くだけのゲームの状態, 足元の地面の高さ};

use super::歩くだけの配線;

impl 歩くだけの配線 {
    // 中心を持たない読み口でも据え直しを条件なしで通す。中心が無いのは高さ場を持たない世界だけであり、
    // その世界では足元の高さの反映も位置を動かさない。
    pub(in crate::world_execution::game) fn 高さ場の地表へ足元を置き直す(&mut self, 読み口: &高さ場の読み口) {
        if let Some(中心) = 読み口.世界の中心の水平位置() {
            let 向き = self.状態.プレイヤーの位置と向き().向き();
            self.状態 = 歩くだけのゲームの状態::開始時の状態を作る(中心, 向き);
        }
        self.状態 = self.状態.足元の地面の高さを反映した状態を返す(self.足元の地面の高さを求める(読み口));
    }

    fn 足元の地面の高さを求める(&self, 読み口: &高さ場の読み口) -> 足元の地面の高さ {
        crate::world_execution::ground_height::足元の地面の高さへ写す(読み口.大域の水平位置から地表高さを求める(self.状態.プレイヤーの位置と向き().大域位置()))
    }
}
