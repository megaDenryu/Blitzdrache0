//! 目的地も進行段階も持たず、キツネの移動・接地・カメラ追従だけを配線するゲーム。持つのはゲームの状態だけであり、
//! 2つのゲームが共有する状態は世界実行が持ち、1刻みの更新へ借りて渡される。高さ場の地表へ足元を置き直すことは`ground`にある。

mod ground;

use blitz_game::{ゲームの操作意図, 一刻みの移動の入力, 歩くだけのゲームの状態, 移動状態};
use blitz_math::{大域ワールド位置, 秒};

use super::fox_player::プレイヤーのエンティティID;
use super::fox_tour::facing::{キツネが読込時に向いている方位角, 世界での向きを読込時からの回転角へ写す};
use super::一刻みが借りる共有の状態;
use crate::world_execution::contract::{世界の形を尋ねる口の実装エラー, 刻み入力};
use crate::world_execution::world_shape_port::エンジンの問い合わせを包んだ世界の形を尋ねる口;

pub(super) struct 歩くだけの配線 {
    状態: 歩くだけのゲームの状態,
}

impl 歩くだけの配線 {
    pub(super) fn 生成する() -> Self {
        Self {
            状態: 歩くだけのゲームの状態::開始時の状態を作る(大域ワールド位置::原点(), キツネが読込時に向いている方位角()),
        }
    }

    // 世界の形を尋ねる口は刻みごとに組み、使い終えたら捨てる(口がその描画のストリーミング調停の借用に縛られるためである)。
    pub(super) fn 一刻み進める(&mut self, 入力: 刻み入力<'_>, 一刻みの秒: 秒, 共有: 一刻みが借りる共有の状態<'_>) -> Result<(), 世界の形を尋ねる口の実装エラー> {
        let 移動の入力 = 一刻みの移動の入力 {
            意図: 共有.操作の適用方針.通す(ゲームの操作意図::確定済みの操作入力から写す(入力.操作入力())),
            刻み: 一刻みの秒,
            前へ進む向き: 入力.前へ進む向きの方位角(),
        };
        let mut 口 = エンジンの問い合わせを包んだ世界の形を尋ねる口::組む(共有.高さ場の読み口, 入力.出どころ())?;
        let (状態, 観測) = self.状態.一刻み進めた状態を返す(&mut 口, &移動の入力)?;
        drop(口);
        self.状態 = 状態;
        共有.移動の記録.刻みの観測を記録する(観測);
        let プレイヤー = self.状態.プレイヤーの位置と向き();
        共有
            .台帳
            .刻みで確定した大域の位置と向きを書き込む(プレイヤーのエンティティID, プレイヤー.大域位置(), 世界での向きを読込時からの回転角へ写す(プレイヤー.向き()));
        Ok(())
    }

    pub(super) fn プレイヤーの大域位置(&self) -> 大域ワールド位置 {
        self.状態.プレイヤーの位置と向き().大域位置()
    }

    pub(super) fn プレイヤーの移動状態(&self) -> 移動状態 {
        self.状態.プレイヤーの移動状態()
    }
}
