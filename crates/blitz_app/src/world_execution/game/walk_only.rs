//! 目的地も進行段階も持たず、キツネの移動・接地・カメラ追従だけを配線するゲーム。持つのはゲームの状態だけであり、
//! 2つのゲームが共有する状態は世界実行が持ち、1刻みの更新へ借りて渡される。高さ場の地表へ足元を置き直すことは`ground`にある。
//!
//! 処理の契約(判断13)は段ごとに1つである。操作入力の適用の段と意図の生成の段はこの配線の状態を読まず書かず、
//! ゲーム配線の振り分けが写した意図をそのまま決定へ載せる(進行段階を持たないため遷移は無く、常に移動を行う)。
//! 移動と作用の要求の段は、決定の移動の入力・高さ場の読み口・出どころを読み、ゲームの状態と移動の記録を書く。
//! ゲームの状態遷移の段は目的地を持たないため何もしない。台帳へはどの段も書かず、確定した位置と向きは`プレイヤーの位置と向き`で答え、
//! 刻みの確定の段で世界実行が台帳へ写す。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」。

mod ground;

use blitz_engine::height_field::高さ場の読み口;
use blitz_game::{プレイヤーの位置と向き, 一刻みの移動の入力, 歩くだけのゲームの状態, 移動状態};
use blitz_math::大域ワールド位置;

use super::fox_tour::facing::キツネが読込時に向いている方位角;
use crate::world_execution::contract::{世界の形を尋ねる口の実装エラー, 読込済みチャンクの形の出どころ};
use crate::world_execution::movement_record::移動の観測の記録;
use crate::world_execution::world_shape_port::エンジンの問い合わせを包んだ世界の形を尋ねる口;

pub(in crate::world_execution) struct 歩くだけの配線 {
    状態: 歩くだけのゲームの状態,
}

impl 歩くだけの配線 {
    pub(super) fn 生成する() -> Self {
        Self {
            状態: 歩くだけのゲームの状態::開始時の状態を作る(大域ワールド位置::原点(), キツネが読込時に向いている方位角()),
        }
    }

    // 世界の形を尋ねる口は刻みごとに組み、使い終えたら捨てる(口がその描画のストリーミング調停の借用に縛られるためである)。
    pub(super) fn プレイヤーを一刻み動かす(
        &mut self,
        移動の入力: &一刻みの移動の入力,
        高さ場の読み口: &高さ場の読み口,
        出どころ: 読込済みチャンクの形の出どころ<'_>,
        移動の記録: &mut 移動の観測の記録,
    ) -> Result<(), 世界の形を尋ねる口の実装エラー> {
        let mut 口 = エンジンの問い合わせを包んだ世界の形を尋ねる口::組む(高さ場の読み口, 出どころ)?;
        let (状態, 観測) = self.状態.一刻み進めた状態を返す(&mut 口, 移動の入力)?;
        drop(口);
        self.状態 = 状態;
        移動の記録.刻みの観測を記録する(観測);
        Ok(())
    }

    pub(super) fn プレイヤーの大域位置(&self) -> 大域ワールド位置 {
        self.状態.プレイヤーの位置と向き().大域位置()
    }

    pub(super) fn プレイヤーの位置と向き(&self) -> プレイヤーの位置と向き {
        self.状態.プレイヤーの位置と向き()
    }

    pub(super) fn プレイヤーの移動状態(&self) -> 移動状態 {
        self.状態.プレイヤーの移動状態()
    }
}
