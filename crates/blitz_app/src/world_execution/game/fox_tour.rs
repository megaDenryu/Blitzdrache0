//! クソゲー1本目「キツネの場所巡り」の配線を所有する。持つのはゲーム固有の状態(道順・ゲームの状態・操作の出どころ)だけであり、2つのゲームが共有する状態は世界実行が持ち、1刻みの更新へ借りて渡される。
//!
//! 道順はゲーム側の表から作る。検収のための世界の分岐はこの配線を通らない。
//!
//! 処理の契約(判断13)は段ごとに4つである。操作入力の適用と操作で決まる状態遷移の段は、刻み入力の操作入力と番号・操作の適用方針を読み、
//! 写した操作の意図を返してゲームの状態(進行段階)を書く。意図の生成とこの刻みで規則が行うことの決定の段は、写した意図から組んだ移動の入力と進行段階を読み、
//! `この刻みで規則が行うこと`を返す(何も書かない)。移動と作用の要求の段は、決定の移動の入力・高さ場の読み口・出どころを読み、
//! ゲームの状態(プレイヤー)と移動の記録を書く。世界の結果で決まる状態遷移の段は、道順とプレイヤーの位置を読み、ゲームの状態(場所巡りの進行)を書く。
//! 台帳へはどの段も書かず、確定した位置と向きは`supply`の口で答え、刻みの確定の段で世界実行が台帳へ写す。
//! 写した意図をこの配線が持ち越さず決定に載せて段のあいだを運ぶのは、「まだ写していない」を型で区別するためである。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断4」「判断12」「判断13」。
//! 起動時に1度だけ走る組み立ては`create`にあり、据えた高さ場の地表へ足元と目的地を置き直すことは`ground`にあり、
//! キツネが読込時に向いている方位と描画側への向きの写しは`facing`にあり、ゲーム固有の状態を外へ渡す口は`supply`にある。

