use blitz_engine::height_field::高さ場の読み口;
use blitz_game::{ゲームの操作意図, 一刻みの移動の入力, 場所巡りのゲームの状態, 場所巡りの道順};

use super::scripted_operation::更新回数から台本の操作入力を決める;
use super::この刻みで規則が行うこと;
use crate::cli::ゲーム操作の出どころ;
use crate::input::ゲーム操作の適用方針;
use crate::world_execution::contract::{世界の形を尋ねる口の実装エラー, 刻み入力, 読込済みチャンクの形の出どころ};
use crate::world_execution::movement_record::移動の観測の記録;
use crate::world_execution::world_shape_port::エンジンの問い合わせを包んだ世界の形を尋ねる口;

pub(in crate::world_execution) struct キツネの場所巡りの配線 {
    道順: 場所巡りの道順,
    状態: 場所巡りのゲームの状態,
    操作の出どころ: ゲーム操作の出どころ,
}

impl キツネの場所巡りの配線 {
    // 台本の操作は適用方針を通らない。方針が止めるのは実ウィンドウから届く操作であり、台本は検収が自ら与える決定的な操作である。
    pub(super) fn 操作入力を適用して進行段階を遷移させる(&mut self, 入力: &刻み入力<'_>, 操作の適用方針: ゲーム操作の適用方針) -> ゲームの操作意図 {
        let 意図 = match 更新回数から台本の操作入力を決める(self.操作の出どころ, 入力.固定刻みの番号()) {
            Some(台本の操作入力) => ゲームの操作意図::確定済みの操作入力から写す(台本の操作入力),
            None => 操作の適用方針.通す(ゲームの操作意図::確定済みの操作入力から写す(入力.操作入力())),
        };
        self.状態 = self.状態.操作の意図で進行段階を遷移させた状態を返す(意図);
        意図
    }

    pub(super) fn この刻みで規則が行うことを決める(&self, 移動の入力: 一刻みの移動の入力) -> この刻みで規則が行うこと {
        if self.状態.進行段階().移動と到達判定を行う段階か() {
            この刻みで規則が行うこと::移動と到達判定を行う(移動の入力)
        } else {
            この刻みで規則が行うこと::移動も到達判定も行わない
        }
    }

    // 世界の形を尋ねる口は刻みごとに組み、使い終えたら捨てる(口がその描画のストリーミング調停の借用に縛られるためである)。
    pub(super) fn プレイヤーを一刻み動かす(
        &mut self,
        移動の入力: &一刻みの移動の入力,
        高さ場の読み口: &高さ場の読み口,
        出どころ: 読込済みチャンクの形の出どころ<'_>,
        移動の記録: &mut 移動の観測の記録,
    ) -> Result<(), 世界の形を尋ねる口の実装エラー> {
        let mut 口 = エンジンの問い合わせを包んだ世界の形を尋ねる口::組む(高さ場の読み口, 出どころ)?;
        let (状態, 観測) = self.状態.プレイヤーを一刻み動かした状態と観測を返す(&mut 口, 移動の入力)?;
        drop(口);
        self.状態 = 状態;
        移動の記録.刻みの観測を記録する(観測);
        Ok(())
    }

    pub(super) fn 目的地への到達を判定して場所巡りの進行を進める(&mut self) {
        self.状態 = self.状態.目的地への到達を判定して場所巡りの進行を進めた状態を返す(&self.道順);
    }

    pub(super) fn 終了が決まったか(&self) -> bool {
        self.状態.終了が決まったか()
    }
}
