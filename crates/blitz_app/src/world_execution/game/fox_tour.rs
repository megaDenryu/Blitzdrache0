use blitz_game::{ゲームの操作意図, 一刻みの移動の入力, 場所巡りのゲームの状態, 場所巡りの道順};
use blitz_math::秒;

use super::fox_player::プレイヤーのエンティティID;
use super::scripted_operation::更新回数から台本の操作入力を決める;
use super::一刻みが借りる共有の状態;
use crate::cli::ゲーム操作の出どころ;
use crate::world_execution::contract::{世界の形を尋ねる口の実装エラー, 刻み入力};
use crate::world_execution::world_shape_port::エンジンの問い合わせを包んだ世界の形を尋ねる口;

pub(in crate::world_execution) struct キツネの場所巡りの配線 {
    道順: 場所巡りの道順,
    状態: 場所巡りのゲームの状態,
    操作の出どころ: ゲーム操作の出どころ,
    ゲーム更新の回数: u32,
}

impl キツネの場所巡りの配線 {
    // 確定済みの操作入力をこのゲームの意味へ写し、方針に通してから1刻みだけ状態を進める。
    // 世界の形を尋ねる口は刻みごとに組み、使い終えたら捨てる(口がその描画のストリーミング調停の借用に縛られるためである)。
    pub(super) fn 一刻み進める(&mut self, 入力: 刻み入力<'_>, 一刻みの秒: 秒, 共有: 一刻みが借りる共有の状態<'_>) -> Result<(), 世界の形を尋ねる口の実装エラー> {
        // 台本の操作は適用方針を通らない。方針が止めるのは実ウィンドウから届く操作であり、台本は検収が自ら与える決定的な操作である。
        let 意図 = match 更新回数から台本の操作入力を決める(self.操作の出どころ, self.ゲーム更新の回数) {
            Some(台本の操作入力) => ゲームの操作意図::確定済みの操作入力から写す(台本の操作入力),
            None => 共有.操作の適用方針.通す(ゲームの操作意図::確定済みの操作入力から写す(入力.操作入力())),
        };
        let 移動の入力 = 一刻みの移動の入力 {
            意図,
            刻み: 一刻みの秒,
            前へ進む向き: 入力.前へ進む向きの方位角(),
        };
        let mut 口 = エンジンの問い合わせを包んだ世界の形を尋ねる口::組む(共有.高さ場の読み口, 入力.出どころ())?;
        let (状態, 観測) = self.状態.一刻み進めた状態を返す(&mut 口, &self.道順, &移動の入力)?;
        drop(口);
        self.状態 = 状態;
        共有.移動の記録.刻みの観測を記録する(観測);
        共有
            .台帳
            .刻みで確定した大域の位置と向きを書き込む(プレイヤーのエンティティID, self.状態.プレイヤーの大域位置(), facing::世界での向きを読込時からの回転角へ写す(self.状態.プレイヤーの向き()));
        self.ゲーム更新の回数 = self.ゲーム更新の回数.saturating_add(1);
        Ok(())
    }

    pub(super) fn 終了が決まったか(&self) -> bool {
        self.状態.終了が決まったか()
    }
}
