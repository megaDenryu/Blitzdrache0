//! クソゲー1本目「キツネの場所巡り」の配線を所有する。持つのはゲーム固有の状態(道順・ゲームの状態・操作の出どころ・
//! 更新の回数)だけであり、2つのゲームが共有する状態は世界実行が持ち、1刻みの更新へ借りて渡される。
//!
//! 道順はゲーム側の表から作る。検収のための世界の分岐はこの配線を通らない。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断4」「判断12」。
//! 起動時に1度だけ走る組み立ては`create`にあり、据えた高さ場の地表へ足元と目的地を置き直すことは`ground`にあり、
//! キツネが読込時に向いている方位と描画側への向きの写しは`facing`にあり、ゲーム固有の状態を外へ渡す口は`supply`にある。

