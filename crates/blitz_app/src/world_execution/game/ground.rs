//! ゲーム配線が、据える高さ場の地表へゲーム固有の状態(足元・目的地)を置き直す振り分け。呼ばれるのは世界実行が高さ場を据える
//! ときであり、読み口の保持は世界実行が行い、ここはゲームの状態と台帳の据え直しだけを行う。

use blitz_engine::height_field::高さ場の読み口;

use super::ゲーム配線;
use crate::world_execution::entity_ledger::ゲーム状態の台帳;

impl ゲーム配線 {
    pub(super) fn 高さ場の地表へ足元と目的地を置き直す(&mut self, 読み口: &高さ場の読み口, 台帳: &mut ゲーム状態の台帳) {
        match self {
            Self::ゲームを遊ばない => {}
            Self::キツネの場所巡り(配線) => 配線.高さ場の地表へ足元と目的地を置き直す(読み口, 台帳),
            Self::歩くだけ(配線) => 配線.高さ場の地表へ足元を置き直す(読み口, 台帳),
        }
    }
}
