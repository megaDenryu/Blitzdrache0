//! キツネの場所巡りの配線が、ゲーム固有の状態(位置・移動状態・画面の表示内容・終了時の要約)を外へ渡す口。
//! 触れるのは読むだけであり、状態を進めるのは親モジュールの1刻みの更新だけである。

use blitz_game::{プレイヤーの位置と向き, 移動状態};
use blitz_math::大域ワールド位置;

use super::キツネの場所巡りの配線;
use crate::app::固定刻みの番号;
use crate::cli::遊ぶゲームの指定;
use crate::overlay_ui::ゲーム画面の表示内容;
use crate::world_execution::contract::ゲーム進行の要約;
use crate::world_execution::movement_record::移動の観測の記録;

impl キツネの場所巡りの配線 {
    pub(in crate::world_execution::game) fn プレイヤーの大域位置(&self) -> 大域ワールド位置 {
        self.状態.プレイヤーの大域位置()
    }

    pub(in crate::world_execution::game) fn プレイヤーの位置と向き(&self) -> プレイヤーの位置と向き {
        プレイヤーの位置と向き::生成する(self.状態.プレイヤーの大域位置(), self.状態.プレイヤーの向き())
    }

    pub(in crate::world_execution::game) fn プレイヤーの移動状態(&self) -> 移動状態 {
        self.状態.プレイヤーの移動状態()
    }

    // そのフレームにゲームの画面が出す値。進行段階と巡った数だけを写し、位置も時刻も渡さない。
    pub(in crate::world_execution::game) fn 画面へ重ねる表示内容を作る(&self) -> ゲーム画面の表示内容 {
        ゲーム画面の表示内容 {
            進行段階: self.状態.進行段階(),
            到達済みの目的地数: self.状態.場所巡り().到達済みの目的地数(),
            目的地の総数: self.道順.目的地の総数(),
        }
    }

    // 更新の回数を番号から数えるのは、番号の所有者が時間進行配線であり、このゲームは起動から全ての刻みで走るためである。
    pub(in crate::world_execution::game) fn 進行の要約を作る(&self, 移動の観測: &移動の観測の記録, 終了時の固定刻みの番号: 固定刻みの番号) -> ゲーム進行の要約 {
        ゲーム進行の要約 {
            ゲームの表示名: 遊ぶゲームの指定::キツネの場所巡り(self.操作の出どころ).表示名(),
            ゲーム更新の回数: 終了時の固定刻みの番号.起動から進めた刻みの本数(),
            最後の進行段階の呼び名: self.状態.進行段階().呼び名(),
            到達済みの目的地数: self.状態.場所巡り().到達済みの目的地数(),
            目的地の総数: self.道順.目的地の総数(),
            プレイヤーの大域位置: self.状態.プレイヤーの大域位置(),
            最後の移動状態の呼び名: self.状態.プレイヤーの移動状態().呼び名(),
            移動の観測: 移動の観測.要約する(),
        }
    }
}
