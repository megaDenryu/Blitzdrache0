//! キツネの足元と目的地を、据える高さ場の地表へ置き直す面。触れるフィールドは`状態`と`道順`に限り、台帳と読み口は世界実行から借りる。
//!
//! 高さ場の問い合わせ結果をゲームロジック層の語彙へ写すのがここの役目である。ゲームロジック層は
//! 高さ場アセットの型を1つも知らず、コンポジションルートのこの写しだけが2つの語彙をつなぐ
//! (参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「第1段階の定義」の項目1)。
//!
//! 高さ場の点参照で足元を地表へ置くのは、高さ場を据えるこの据え直しの1箇所だけである。毎刻みの接地は掃引による
//! 接地判定が決める(`_doc/設計/キャラクターの移動とカメラ.md`「判断5」)。据え直しを残すのは、出発地点の天頂成分が0であり、
//! 地表がそれより高い世界では胴体が地面の中から始まって掃引が一歩も動けないためである。
//!
//! 目的地の天頂成分をここで置き直すのは、ゲーム側の表が水平の位置しか決めておらず、天頂成分がその場所の
//! 地表高さで決まるためである。置き直さないと、起伏のある地面ではキツネの足元の高さと目的地の高さが
//! 起伏のぶんだけ食い違い、柱の真下に立っても到達が成立しない。

use blitz_engine::height_field::{地表高さの問い合わせ結果, 高さ場の読み口};
use blitz_game::{場所巡りの道順, 目的地, 足元の地面の高さ};

use super::{facing, キツネの場所巡りの配線};
use crate::world_execution::entity_ledger::ゲーム状態の台帳;
use crate::world_execution::game::fox_player::プレイヤーのエンティティID;

impl キツネの場所巡りの配線 {
    // 呼ばれるのはカタログを構築した起動時の1回と、実行時アセットの差し替えである。
    // 高さ場を持たない世界ではキツネの高さも目的地の高さも動かず、既存の検収の世界はこの選択肢へ落ちる。
    // 足元の据え直しは刻みを1つも進めない跳びであるため、台帳の2枚を前後とも据え直す。
    pub(in crate::world_execution::game) fn 高さ場の地表へ足元と目的地を置き直す(&mut self, 読み口: &高さ場の読み口, 台帳: &mut ゲーム状態の台帳) {
        self.道順 = self.目的地の天頂成分を地表へ置き直した道順を作る(読み口);
        self.状態 = self.状態.足元の地面の高さを反映した状態を返す(self.足元の地面の高さを求める(読み口));
        台帳.跳ばした大域の位置と向きを前後とも据え直す(プレイヤーのエンティティID, self.状態.プレイヤーの大域位置(), facing::世界での向きを読込時からの回転角へ写す(self.状態.プレイヤーの向き()));
    }

    fn 足元の地面の高さを求める(&self, 読み口: &高さ場の読み口) -> 足元の地面の高さ {
        crate::world_execution::ground_height::足元の地面の高さへ写す(読み口.大域の水平位置から地表高さを求める(self.状態.プレイヤーの大域位置()))
    }

    fn 目的地の天頂成分を地表へ置き直した道順を作る(&self, 読み口: &高さ場の読み口) -> 場所巡りの道順 {
        let 置き直した一覧 = self.道順.目的地一覧().iter().map(|目的地| self.天頂成分を地表へ置き直した目的地を作る(読み口, *目的地)).collect();
        場所巡りの道順::生成する(置き直した一覧)
    }

    // 高さが分からない2つの選択肢で天頂成分を動かさないのは、表が持つ0メートルへ落とすのと同じ扱いにするためである。
    // 高さ場を持たない世界ではキツネの天頂成分も動かないため、2つは同じ高さの平面の上に並ぶ。
    // 置き直しをこの配線のメソッドに置くのは、`目的地`が`blitz_game`の型であり`blitz_math`しか知らないため、
    // `blitz_engine`の`高さ場の読み口`を受け取るメソッドを`目的地`自身へ置けないためである。
    fn 天頂成分を地表へ置き直した目的地を作る(&self, 読み口: &高さ場の読み口, 目的地: 目的地) -> 目的地 {
        match 読み口.大域の水平位置から地表高さを求める(目的地.大域位置()) {
            地表高さの問い合わせ結果::高さ場を持たない世界 | 地表高さの問い合わせ結果::高さ場の広がりの外 => 目的地,
            地表高さの問い合わせ結果::地表高さ(高さ) => 目的地.天頂成分を据えた目的地を返す(高さ),
        }
    }
}
