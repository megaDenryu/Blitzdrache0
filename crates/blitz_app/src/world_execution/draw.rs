//! 世界実行の描画機会の入口。描画機会の更新(供給値の混ぜ直しと表示距離の決定)、描画機会の抽出(注視点・描画供給・
//! 動く個体の指定一覧の預け渡し)、終了時の要約を持つ。どれもゲームの確定状態を1つも書き換えない。
//!
//! 注視点を描画供給と別の口にするのは、注視点がカメラの更新より前に要り、表示距離と計器がカメラの更新の後に決まるためである。
//! 注視点は台帳の確定値を割合で混ぜて求めるため、指定一覧の混ぜ直しの前後で値は変わらない。
//! 世界の形を尋ねる口をここで組むのは、口が高さ場の読み口とストリーミング調停(アプリが持つ)の両方を借りるためである。
//! 参照: `_doc/設計/時間の規律.md`「判断5」「判断6」、`_doc/設計/ゲーム制作アーキテクチャ.md`「判断12」。

use blitz_game::移動状態;
use blitz_math::大域ワールド位置;
use blitz_render::frame_input::動く個体の大域の位置と向きの指定;

use super::contract::{この描画のカメラの入力, ゲーム進行の要約, 世界の形を尋ねる口の実装エラー, 描画供給, 移動とカメラの計器, 表示距離の指示, 読込済みチャンクの形の出どころ};
use super::world_shape_port::エンジンの問い合わせを包んだ世界の形を尋ねる口;
use super::世界実行;
use crate::app::{固定刻みの番号, 描画補間の割合};

impl 世界実行 {
    /// カメラの注視点にする、この描画の割合で混ぜた足元の大域位置に目の高さを足した点。遊ばない起動では`None`であり、
    /// カメラは起動時の姿勢とマウス操作だけで決まる。描くその個体と同じ混ぜた位置から導くため、注視点と個体の位置関係は画面上で動かない。
    pub(crate) fn カメラの注視点にする混ぜた大域位置(&self, 割合: 描画補間の割合) -> Option<大域ワールド位置> {
        let エンティティid = self.ゲーム配線.刻み境界で確定したプレイヤー()?.エンティティid();
        Some(self.カメラ.注視点を足元から求める(self.台帳.エンティティの混ぜた大域位置を求める(エンティティid, 割合)))
    }

    /// 描画へ渡す指定の列をこの描画の割合で混ぜ直し、この描画の表示距離を遮蔽から決める。
    /// 問い合わせの失敗は型付きエラーで上へ返し、黙って理想距離へ落とさない。遊ばない起動ではカメラを触らない。
    pub(crate) fn この描画の世界を描画機会の時間意味で更新する(
        &mut self,
        割合: 描画補間の割合,
        出どころ: 読込済みチャンクの形の出どころ<'_>,
        入力: この描画のカメラの入力,
    ) -> Result<表示距離の指示, 世界の形を尋ねる口の実装エラー> {
        self.台帳.描画へ渡す指定一覧をこの描画の割合で混ぜ直す(割合);
        if !self.ゲーム配線.ゲームを遊ぶか() {
            return Ok(表示距離の指示::カメラを触らない);
        }
        let mut 口 = エンジンの問い合わせを包んだ世界の形を尋ねる口::組む(&self.高さ場の読み口, 出どころ)?;
        Ok(表示距離の指示::据える(self.カメラ.この描画の表示距離を決める(&mut 口, 入力)?))
    }

    /// 画面へ重ねるUIが読む、この描画の描画供給。1描画に1度、表示距離を決めた後に作る。
    pub(crate) fn この描画の描画供給を作る(&self) -> 描画供給 {
        描画供給 {
            画面へ重ねる表示内容: self.ゲーム配線.画面へ重ねる表示内容を作る(),
            移動とカメラの計器: self.ゲーム配線.プレイヤーの移動状態().map(|移動状態| self.移動とカメラの計器を作る(移動状態)),
        }
    }

    fn 移動とカメラの計器を作る(&self, 移動状態: 移動状態) -> 移動とカメラの計器 {
        移動とカメラの計器 {
            移動: self.移動の記録.計器を作る(移動状態),
            カメラ: self.カメラ.計器を作る(),
        }
    }

    /// そのフレームの描画入力が借用する動く個体の位置の列を預ける。遊ばない起動では空の列であり、確保も書き込みも起こらない。
    pub(crate) fn 動く個体の大域の位置と向きの指定一覧を預ける(&mut self) -> Vec<動く個体の大域の位置と向きの指定> {
        self.台帳.指定一覧を預ける()
    }

    pub(crate) fn 動く個体の大域の位置と向きの指定一覧を戻す(&mut self, 受け皿: Vec<動く個体の大域の位置と向きの指定>) {
        self.台帳.指定一覧を戻す(受け皿);
    }

    /// 終了時の報告へ渡す要約。報告する対象を持たないゲームと遊ばない起動では`None`を返す。
    /// 番号を受けるのは、報告の「ゲーム更新の回数」が起動から進めた固定刻みの本数であり、番号の所有者が時間進行配線だからである。
    pub(crate) fn 進行の要約を作る(&self, 終了時の固定刻みの番号: 固定刻みの番号) -> Option<ゲーム進行の要約> {
        self.ゲーム配線.進行の要約を作る(&self.移動の記録, 終了時の固定刻みの番号)
    }
}
