//! 世界実行の固定刻みの入口。1描画に1度の操作入力の確定と、刻みごとの更新・所要時間の記録・刻み境界の確定位置を持つ。
//! 呼ばれるのは刻みを回す工程(`app/frame/game_steps.rs`)からであり、描画機会ごとの入口とは呼び出しの頻度が違う。
//!
//! 1刻みは`固定刻みの段の並び`(`tick_stage`)を先頭から順に回し、段ごとの`match`で処理を呼ぶ。11段すべてが`match`の選択肢に
//! 現れるため、段を足したときに処理の置き場を決め忘れることをコンパイラが止める。処理を持たない段は空の選択肢である。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」。
//!
//! 処理の契約(段・読む状態・書く状態)は5つである。操作入力の適用と操作で決まる状態遷移の段(`操作入力を適用して進行段階を遷移させる`)は
//! 刻み入力の操作入力と番号・操作の適用の方式を読み、ゲーム固有の状態(進行段階)を書き、写した意図を決定へ載せる。意図の生成とこの刻みで規則が行うことの決定の段
//! (`この刻みで規則が行うことを決める`)は決定の写した意図・遷移後の進行段階・刻み入力の前へ進む向きを読み、決定を
//! 移動と到達判定を行うか行わないかへ進める。決定`この刻みで規則が行うこと`は段のあいだを運ぶ1本の局所変数であり、この刻みの規則の進みを表す。移動と作用の要求の段(`プレイヤーを一刻み動かす`)は決定・刻み入力の出どころ・高さ場の読み口を
//! 読み、ゲーム固有の状態(プレイヤー)と移動の記録を書く。行わない刻みでも観測を1件記録する。世界の結果で決まる状態遷移の段
//! (`目的地への到達を判定して場所巡りの進行を進める`)は決定と道順を読み、場所巡りの進行を書く。刻みの確定の段は
//! ゲーム配線が答える`刻み境界で確定したプレイヤー`と終了が決まったかを読み、ゲーム状態の台帳を書いて刻み結果を組む。
//! 遊ばない起動はプレイヤーを持たないため台帳へ1件も書かない。規則の各段の変換は`blitz_game`が持ち、段の順序はこの工程が持つ。
//! 不変条件「メニューの裏で位置が動かず到達しない」の判定は意図の生成とこの刻みで規則が行うことの決定の段の1箇所であり、後続の2段は決定に従う。
//!
//! 読込済みチャンクの形の出どころを刻み入力に載せて受け取るのは、世界の形を尋ねる口がその描画のストリーミング調停の借用に
//! 縛られ、世界実行が持ち越せないためである。出どころが運ぶ形の版を刻みごとに記録するのは、1つの描画の全刻みが同じ形を
//! 見たことを終了時の報告で観測させるためである。低頻度の処理は0件であり、周期はこの工程が持つ。

use std::time::Duration;

use blitz_math::{ラジアン, 大域ワールド位置, 秒};

use super::contract::{世界の形を尋ねる口の実装エラー, 刻み入力, 刻み結果};
use super::game::この刻みで規則が行うこと;
use super::tick_stage::{固定刻みの段, 固定刻みの段の並び};
use super::世界実行;
use crate::app::進める刻み数;
use crate::input::{入力状態, 刻みごとの操作入力};

impl 世界実行 {
    /// 1描画に1度だけ操作入力を確定し、その描画で進める刻みへ配る器を作る。遊ばない起動は操作の確定すら行わず`None`を返す。
    /// 確定を刻みごとに行わないのは、入力の確定が描画の頻度で起きるためである。
    ///
    /// カメラの系統の切替の操作は確定した直後にここで受け取る。刻みへ配らないのは、系統がゲームの状態でなく描画機会ごとの
    /// カメラの関心であり、1描画に1度だけ効けばよいためである。刻み0本の描画では確定しないため旗は保持される。
    ///
    /// カメラのヨーを値で受けて器に載せるのは、ヨーを読む地点をこの呼び出しに閉じ、刻みを回す工程が刻みごとにヨーを渡さない
    /// ためである。渡すヨーがこの描画のカメラ操作を反映する前の値であることは、呼び出し側の工程の並びが守る(判断13)。
    ///
    /// 刻みを1本も進めない描画で入力を確定しないのは、確定が決定・取り消しの押し下げの旗を消費するためである。
    /// 毎秒120回書き換えるモニターでは刻み0本の描画が半分を占め、そこで確定すると、押して次の刻みより前に離した
    /// 操作がゲームへ一度も届かない。無期限実行の最初の描画は必ず0本のため、起動直後の押し下げにも同じ穴が開く。
    pub(crate) fn この描画で進める刻みへ配る操作入力を確定する(&mut self, 入力状態: &mut 入力状態, 刻み数: 進める刻み数, カメラのヨー: ラジアン) -> Option<刻みごとの操作入力> {
        if 刻み数.一本も進めないか() || !self.ゲーム配線.ゲームを遊ぶか() {
            return None;
        }
        let 入力 = 入力状態.ゲームの操作入力を確定する();
        self.カメラ.切替の操作を受け取る(入力.カメラの系統を切り替える操作を押した瞬間か);
        Some(刻みごとの操作入力::一描画の確定から生成する(入力, カメラのヨー))
    }

    /// ゲーム更新を1刻みだけ行う。刻みの長さを受け取るのは、時間の進め方をこの型が持たないためである。
    /// 終了が決まった刻みでも刻みの確定の段まで回すのは、終了を決めた刻みの確定した位置を描画へ供給するためである。
    /// 決定を段のループの前に「まだ決まっていない」で置くのは、操作入力の適用と操作で決まる状態遷移・意図の生成とこの刻みで規則が行うことの決定・移動の順が壊れた並びを決定を読む口が止めるためである。
    pub(crate) fn 一刻み進める(&mut self, 入力: 刻み入力<'_>, 一刻みの秒: 秒) -> Result<刻み結果, 世界の形を尋ねる口の実装エラー> {
        self.移動の記録.刻みが見た世界の形の版を記録する(入力.出どころ().版());
        let mut 決定 = この刻みで規則が行うこと::まだ決まっていない;
        for 段 in 固定刻みの段の並び {
            match 段 {
                固定刻みの段::前刻みからの構造変更の確定 => {} // 処理は0件。Issue #55(構造変更)が足す
                固定刻みの段::操作入力の適用と操作で決まる状態遷移 => {
                    決定 = この刻みで規則が行うこと::操作の意図を写した(self.ゲーム配線.操作入力を適用して進行段階を遷移させる(&入力, self.操作の適用の方式))
                }
                固定刻みの段::意図の生成とこの刻みで規則が行うことの決定 => 決定 = self.ゲーム配線.この刻みで規則が行うことを決める(決定.写した操作の意図を返す(), &入力, 一刻みの秒),
                固定刻みの段::移動と作用の要求 => self.ゲーム配線.プレイヤーを一刻み動かす(&決定, &入力, &self.高さ場の読み口, &mut self.移動の記録)?,
                固定刻みの段::物理への入力 | 固定刻みの段::物理を一刻み進める | 固定刻みの段::物理の結果の反映 => {} // 処理は0件。Issue #43(物理)が足す
                固定刻みの段::世界の結果で決まる状態遷移 => self.ゲーム配線.目的地への到達を判定して場所巡りの進行を進める(&決定),
                固定刻みの段::アニメーション等のゲーム上必要な状態更新 => {} // 処理は0件。アニメーション時刻は描画機会に1回まとめて走る
                固定刻みの段::構造変更の予約 => {}                           // 処理は0件。Issue #55(構造変更)が足す
                固定刻みの段::刻みの確定 => {
                    if let Some(確定したプレイヤー) = self.ゲーム配線.刻み境界で確定したプレイヤー() {
                        self.台帳.刻みで確定したプレイヤーを供給値へ書き込む(確定したプレイヤー);
                    }
                }
            }
        }
        Ok(刻み結果::終了が決まったかから組む(self.ゲーム配線.終了が決まったか()))
    }

    /// 刻みを回す工程が測った1刻みの所要時間を記録へ渡す。時計を読むのは工程であり、この型は足すだけである。
    pub(crate) fn 刻みの所要時間を記録する(&mut self, 所要時間: Duration) {
        self.移動の記録.刻みの所要時間を記録する(所要時間);
    }

    /// 刻み境界で確定したプレイヤーの大域位置。遊ばない起動では`None`である。
    /// 混ぜた値でなく確定値を返すのは、この口を読むのがストリーミングの必要チャンク集合の中心だからである。
    /// 常駐するチャンクの集合はゲームが読む高さ場を決めるため、混ぜた値をここへ通すと、描画のためだけに作った値が
    /// 次のゲーム更新の入力へ回り込む(参照: `_doc/設計/時間の規律.md`「判断6」)。
    pub(crate) fn 刻み境界で確定したプレイヤーの大域位置(&self) -> Option<大域ワールド位置> {
        self.ゲーム配線.刻み境界で確定したプレイヤーの大域位置()
    }
}
