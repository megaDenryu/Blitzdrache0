//! 固定刻みの処理位置の並びが実行順の真実であることの検証。見るのは3つである。移動を行わない刻み(タイトル表示中)でも
//! 移動と作用の要求の処理位置が観測を1件記録し、その刻みの所要時間の記録が止まらないこと。操作入力の適用と操作で決まる状態遷移の処理位置より前に
//! 意図の生成とこの刻みで規則が行うことの決定の処理位置を回すと、まだ写されていない意図を読んだ口が止まること。意図の生成とこの刻みで規則が行うことの決定の処理位置より前に
//! 移動と作用の要求の処理位置を回すと、まだ決まっていない決定を読んだ口が止まること。
//! 処理位置の並びは`固定刻みの処理位置の並び`の定数であり差し替えられないため、後の2つは世界実行の入口を通さず、ゲーム配線の処理位置の口を
//! 前の処理位置が進めていない決定で直接呼んで固定する。台本の区切りが1刻みもずれないことは`app/frame/game_steps_tests.rs`が見る。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」。

use std::time::Duration;

use blitz_engine::height_field::高さ場の読み口;
use blitz_game::確定済みの操作入力;
use blitz_math::ラジアン;

use super::contract::{刻み入力, 読込済みチャンクの形の出どころ};
use super::game::{この刻みで規則が行うこと, ゲーム配線};
use super::movement_record::移動の観測の記録;
use super::世界実行;
use crate::app::固定刻みの番号;
use crate::cli::{ゲーム操作の出どころ, 起動モード, 遊ぶゲームの指定};
use crate::input::刻みごとの操作入力;

fn 台本のキツネの場所巡り() -> 遊ぶゲームの指定 {
    遊ぶゲームの指定::キツネの場所巡り(ゲーム操作の出どころ::決定的な台本)
}

/// 反証: タイトル表示中の刻みで観測を記録しないと、刻みを回す工程が渡す所要時間が観測の無い刻みへ届いて止まる。
#[test]
fn タイトル表示中の刻みでも移動の観測が1件記録され所要時間の記録が止まらない() {
    let mut 世界実行 = 世界実行::起動設定から作る(台本のキツネの場所巡り(), 起動モード::スモーク実行 { 描画機会の数: 1 });
    let mut 器 = 刻みごとの操作入力::一描画の確定から生成する(確定済みの操作入力::無操作(), ラジアン::生成する(0.0));
    let 入力 = 刻み入力::配る器から次の刻みぶんを生成する(&mut 器, 読込済みチャンクの形の出どころ::ストリーミングを使わない起動, 固定刻みの番号::起動時の最初());
    let 結果 = 世界実行.一刻み進める(入力, super::ゲーム更新の一刻みの秒());
    assert!(結果.is_ok());
    世界実行.刻みの所要時間を記録する(Duration::from_micros(1));
}

/// 反証: 操作入力の適用と操作で決まる状態遷移の処理位置より前に意図の生成とこの刻みで規則が行うことの決定の処理位置が回ると、写した意図が無いまま読まれる。
/// 黙って通す(無操作の意図で埋める)と、処理位置の並びの誤りが「操作が届かない刻み」として現れ、工程が止められない。
#[test]
#[should_panic(expected = "この刻みの操作の意図がまだ写されていない")]
fn 操作入力の適用と操作で決まる状態遷移の処理位置より前に意図の生成とこの刻みで規則が行うことの決定の処理位置を回すと止まる() {
    let ゲーム配線 = ゲーム配線::起動設定から作る(台本のキツネの場所巡り());
    let mut 器 = 刻みごとの操作入力::一描画の確定から生成する(確定済みの操作入力::無操作(), ラジアン::生成する(0.0));
    let 入力 = 刻み入力::配る器から次の刻みぶんを生成する(&mut 器, 読込済みチャンクの形の出どころ::ストリーミングを使わない起動, 固定刻みの番号::起動時の最初());
    let 決定 = この刻みで規則が行うこと::まだ決まっていない;
    let 進めた決定 = ゲーム配線.この刻みで規則が行うことを決める(決定.写した操作の意図を返す(), &入力, super::ゲーム更新の一刻みの秒());
    assert!(進めた決定.移動と到達判定を行うなら移動の入力を返す().is_none(), "検査の前提: ここへ到達したなら決定を読む口が止まっていない");
}

/// 反証: 意図の生成とこの刻みで規則が行うことの決定の処理位置より前に移動と作用の要求の処理位置が回ると、決定が「まだ決まっていない」のまま読まれる。
/// 黙って通すと、処理位置の並びの誤りが移動の有無として現れず、メニューの裏で位置が動く不変条件の破れを工程が止められない。
#[test]
#[should_panic(expected = "この刻みで規則が行うことがまだ決まっていない")]
fn 意図の生成とこの刻みで規則が行うことの決定の処理位置より前に移動と作用の要求の処理位置を回すと止まる() {
    let mut ゲーム配線 = ゲーム配線::起動設定から作る(台本のキツネの場所巡り());
    let mut 移動の記録 = 移動の観測の記録::まだ刻んでいない記録を作る();
    let mut 器 = 刻みごとの操作入力::一描画の確定から生成する(確定済みの操作入力::無操作(), ラジアン::生成する(0.0));
    let 入力 = 刻み入力::配る器から次の刻みぶんを生成する(&mut 器, 読込済みチャンクの形の出どころ::ストリーミングを使わない起動, 固定刻みの番号::起動時の最初());
    let 結果 = ゲーム配線.プレイヤーを一刻み動かす(&この刻みで規則が行うこと::まだ決まっていない, &入力, &高さ場の読み口::高さ場を持たない世界, &mut 移動の記録);
    assert!(結果.is_ok(), "検査の前提: ここへ到達したなら決定を読む口が止まっていない");
}
