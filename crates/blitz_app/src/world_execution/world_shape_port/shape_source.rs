//! 読込済みチャンクの形の出どころ: その描画の世界の形を尋ねる口が、建物の形をどこから読むかの選択肢。
//!
//! `Option`でなく選択肢で持つのは、ストリーミングを使わない起動が「建物を1棟も持たない世界」という確定した事実であり、
//! 無いことを消費側の分岐へ波及させないためである。フレームの工程がアプリのストリーミング配線から組んでゲーム配線へ渡す。
//!
//! 出どころは調停の共有借用であるため、1つの描画の全刻みは同じ版の形を見る。刻みが版を記録するのは、その性質を文の並び順
//! でなく観測で確かめるためである。

use blitz_engine::{ストリーミング調停, 読込済みチャンクの形の版};

#[derive(Clone, Copy)]
pub(crate) enum 読込済みチャンクの形の出どころ<'調停> {
    ストリーミングを使わない起動,
    ストリーミング調停(&'調停 ストリーミング調停),
}

impl 読込済みチャンクの形の出どころ<'_> {
    /// この出どころが運ぶ形の版。ストリーミングを使わない起動は形が変わらないため、常に最初の版である。
    pub(crate) fn 版(self) -> 読込済みチャンクの形の版 {
        match self {
            Self::ストリーミングを使わない起動 => 読込済みチャンクの形の版::最初を作る(),
            Self::ストリーミング調停(調停) => 調停.読込済みチャンクの形の版(),
        }
    }
}
