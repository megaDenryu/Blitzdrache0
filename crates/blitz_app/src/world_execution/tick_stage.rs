//! 固定刻みの段と、工程がそれを回す順序(工程の段の順序)。担当するのは段の名前と並びを1箇所で持つことだけであり、
//! 各段で何が走るかは世界実行の固定刻みの入口が持つ。
//!
//! 並びはIssue #50の本文の10段と`_doc/設計/ゲーム実行基盤.md`第6節の10段の和集合の11段である。処理を持たない段も
//! 名前のある位置として残す。段の順序はここが所有し、規則の各段の変換(遷移・移動・到達判定)は`blitz_game`が所有する。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」。

/// 固定刻みの工程が1刻みぶんの処理を回す位置。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 固定刻みの段 {
    /// 前の刻みが予約した構造変更を反映して確定する段
    前刻みからの構造変更の確定,
    /// 確定済みの操作入力を世界へ適用する段
    操作入力の適用,
    /// プレイヤーとAIの意図を生成する段
    意図の生成,
    /// 移動と作用の要求を生成する段
    移動と作用の要求,
    /// 物理世界へ入力を確定する段
    物理への入力,
    /// 物理世界を一刻み進める段
    物理を一刻み進める,
    /// 接触と物理の結果をゲーム世界へ反映する段
    物理の結果の反映,
    /// キャラクターと相互作用のゲームの状態遷移の段
    ゲームの状態遷移,
    /// アニメーション等のゲーム上必要な状態更新の段
    アニメーション等のゲーム上必要な状態更新,
    /// 寿命と破壊等の構造変更を予約する段
    構造変更の予約,
    /// 刻みの結果を確定して供給値を台帳へ書く段
    刻みの確定,
}

/// 工程の段の順序。世界実行の固定刻みの入口はこの並びを先頭から順に回す。
pub(super) const 固定刻みの段の並び: [固定刻みの段; 11] = [
    固定刻みの段::前刻みからの構造変更の確定,
    固定刻みの段::操作入力の適用,
    固定刻みの段::意図の生成,
    固定刻みの段::移動と作用の要求,
    固定刻みの段::物理への入力,
    固定刻みの段::物理を一刻み進める,
    固定刻みの段::物理の結果の反映,
    固定刻みの段::ゲームの状態遷移,
    固定刻みの段::アニメーション等のゲーム上必要な状態更新,
    固定刻みの段::構造変更の予約,
    固定刻みの段::刻みの確定,
];
