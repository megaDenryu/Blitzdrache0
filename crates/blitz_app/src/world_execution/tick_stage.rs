//! 固定刻みの処理位置と、工程がそれを回す順序。担当するのは処理位置の名前と並びを1箇所で持つことだけであり、
//! 各処理位置で何が走るかは世界実行の固定刻みの入口が持つ。
//!
//! 並びはIssue #50の本文の10個と`_doc/設計/ゲーム実行基盤.md`第6節の10個の和集合の11個である。処理を持たない位置も
//! 名前のある位置として残す。順序はここが所有し、規則の各処理位置の変換(遷移・移動・到達判定)は`blitz_game`が所有する。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」。

/// 固定刻みの工程が1刻みぶんの処理を回す位置。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 固定刻みの処理位置 {
    /// 前の刻みが予約した構造変更を反映して確定する処理位置
    前刻みからの構造変更の確定,
    /// 確定した操作入力を操作の意図へ写し、操作だけで決まる進行段階(タイトル・終了確認・終了決定などのメニューの段階)を遷移させる処理位置
    操作入力の適用と操作で決まる状態遷移,
    /// 移動の意図(一刻みの移動の入力)を組み、この刻みで規則が行うことを決める処理位置。将来のAIの意図の生成もここに入る
    意図の生成とこの刻みで規則が行うことの決定,
    /// 移動と作用の要求を生成する処理位置
    移動と作用の要求,
    /// 物理世界へ入力を確定する処理位置
    物理への入力,
    /// 物理世界を一刻み進める処理位置
    物理を一刻み進める,
    /// 接触と物理の結果をゲーム世界へ反映する処理位置
    物理の結果の反映,
    /// 移動・物理・接触の結果で決まる状態遷移の処理位置(目的地への到達による場所巡りの進行の更新など)。`ゲームの進行段階`はここでは書かない
    世界の結果で決まる状態遷移,
    /// アニメーション等のゲーム上必要な状態更新の処理位置
    アニメーション等のゲーム上必要な状態更新,
    /// 寿命と破壊等の構造変更を予約する処理位置
    構造変更の予約,
    /// 刻みの結果を確定して供給値を台帳へ書く処理位置
    刻みの確定,
}

/// 固定刻みの工程が処理位置を回す順序。世界実行の固定刻みの入口はこの並びを先頭から順に回す。
pub(super) const 固定刻みの処理位置の並び: [固定刻みの処理位置; 11] = [
    固定刻みの処理位置::前刻みからの構造変更の確定,
    固定刻みの処理位置::操作入力の適用と操作で決まる状態遷移,
    固定刻みの処理位置::意図の生成とこの刻みで規則が行うことの決定,
    固定刻みの処理位置::移動と作用の要求,
    固定刻みの処理位置::物理への入力,
    固定刻みの処理位置::物理を一刻み進める,
    固定刻みの処理位置::物理の結果の反映,
    固定刻みの処理位置::世界の結果で決まる状態遷移,
    固定刻みの処理位置::アニメーション等のゲーム上必要な状態更新,
    固定刻みの処理位置::構造変更の予約,
    固定刻みの処理位置::刻みの確定,
];
