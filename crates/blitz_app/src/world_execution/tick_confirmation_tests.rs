//! 刻みの確定の処理位置が、プレイヤーの確定した位置と向きをゲーム状態の台帳へ書き込むことの検証。台帳へ書くのが世界実行の
//! 固定刻みの入口であることは、ゲーム配線の側に台帳への口が無いこと(型)と、この検査(値)の両方で固定する。
//! 台本で31本より多く回すのは、決定の次の刻みから前へ進む操作が入り、確定した位置が出発地点から動くためである。
//! 平坦な高さ場を据えるのは、高さ場を持たない世界では移動の掃引が評価できない領域で止まるためである。
//! 世界実行の私有のフィールドをこの検査が読めるのは、検査が世界実行のモジュールの木の中にあるためである。
//! 向きを数値の期待値と比べないのは、向きが1刻みに回れる角の上限で目標へ寄っていく値であり、刻みの後の角が北へ
//! 誤差なく一致する保証が無く、しかも読込時の向きから回す角がこのクレートへラジアンの読み口を開けていないためである。
//! 代わりに、台帳の角が出発の角から動いたことと、ゲーム配線が答える角と一致することの2つで固定する。向きの写しを固定値へ
//! 差し替えると、出発の角(登録時に同じ写しで書く)と刻みの後の角が同じ固定値になり、前者が落ちる。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」。

#![allow(clippy::unwrap_used)]

use blitz_engine::height_field::{高さ場, 高さ場の読み口, 高さ場諸元};
use blitz_game::確定済みの操作入力;
use blitz_math::{メートル, ラジアン, 大域メートル};
use blitz_render::frame_input::読込時の向きから天頂軸まわりに回す角;

use super::contract::{ゲーム用高さ場, 刻み入力, 読込済みチャンクの形の出どころ};
use super::世界実行;
use crate::app::{固定刻みの番号, 描画補間の割合};
use crate::cli::{ゲーム操作の出どころ, 起動モード, 遊ぶゲームの指定};
use crate::input::刻みごとの操作入力;

fn 平坦な高さ場を作る() -> 高さ場 {
    let 諸元 = 高さ場諸元::生成する(大域メートル::生成する(-100.0), 大域メートル::生成する(-100.0), メートル::生成する(100.0), 3, 3).unwrap();
    高さ場::生成する(諸元, vec![メートル::生成する(0.0); 9]).unwrap()
}

// 台帳が現在の確定値そのものとして描画へ渡す、プレイヤーの読込時の向きから回す角。台帳は角の読み口を持たず、描画へ渡す指定の列から読む。
fn 台帳が描画へ渡すプレイヤーの回す角(世界実行: &mut 世界実行) -> 読込時の向きから天頂軸まわりに回す角 {
    世界実行.台帳.描画へ渡す指定一覧をこの描画の割合で混ぜ直す(描画補間の割合::現在の確定値そのもの());
    let 指定一覧 = 世界実行.台帳.指定一覧を預ける();
    let 回す角 = 指定一覧[0].読込時の向きから回す角;
    世界実行.台帳.指定一覧を戻す(指定一覧);
    回す角
}

/// 反証: 刻みの確定の処理位置が台帳へ書かないと、ゲームの状態は北へ進むのに台帳の供給値が出発地点のまま残り、描かれるキツネが動かない。
/// 向きは、南を向いて出発したキツネが北へ進みながら向きを変えるため、刻みの後の角が出発の角から動く。
#[test]
fn 刻みの確定の処理位置はプレイヤーの確定した位置を台帳の供給値へ写す() {
    let mut 世界実行 = 世界実行::起動設定から作る(遊ぶゲームの指定::キツネの場所巡り(ゲーム操作の出どころ::決定的な台本), 起動モード::スモーク実行 { 描画機会の数: 1 });
    世界実行.高さ場を据える(ゲーム用高さ場::読み込んだ(高さ場の読み口::高さ場を持つ世界(平坦な高さ場を作る())));
    let 出発地点 = 世界実行.刻み境界で確定したプレイヤーの大域位置().unwrap();
    let 出発の回す角 = 台帳が描画へ渡すプレイヤーの回す角(&mut 世界実行);
    let mut 器 = 刻みごとの操作入力::一描画の確定から生成する(確定済みの操作入力::無操作(), ラジアン::生成する(0.0));
    let mut 番号 = 固定刻みの番号::起動時の最初();
    for _ in 0..60 {
        let 入力 = 刻み入力::配る器から次の刻みぶんを生成する(&mut 器, 読込済みチャンクの形の出どころ::ストリーミングを使わない起動, 番号);
        世界実行.一刻み進める(入力, super::ゲーム更新の一刻みの秒()).unwrap();
        番号 = 番号.本数だけ後の番号(1);
    }
    let 確定した位置 = 世界実行.刻み境界で確定したプレイヤーの大域位置().unwrap();
    assert!(確定した位置.z() < 出発地点.z(), "検査の前提: 台本の前へ進む操作で北(Zの負の向き)へ進む");
    let 確定したプレイヤー = 世界実行.ゲーム配線.刻み境界で確定したプレイヤー().unwrap();
    assert_eq!(世界実行.台帳.エンティティの混ぜた大域位置を求める(確定したプレイヤー.エンティティid(), 描画補間の割合::現在の確定値そのもの()), 確定した位置);
    let 確定した回す角 = 台帳が描画へ渡すプレイヤーの回す角(&mut 世界実行);
    assert_ne!(確定した回す角, 出発の回す角, "検査の前提: 南を向いて出発したキツネが北へ進み、向きが出発から動く");
    assert_eq!(確定した回す角, 確定したプレイヤー.読込時の向きから回す角());
}
