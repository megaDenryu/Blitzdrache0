//! 固定刻みの処理位置の並びを実際に通る経路での検証。見るのは2つである。操作入力の適用と操作で決まる状態遷移の段が意図の生成とこの刻みで規則が行うことの決定の段より前にあるため、
//! 決定と前進を同時に含む刻みで場所巡り中へ入りながら同じ刻みのうちに位置が動くこと。刻みの確定の段が組む刻み結果が、
//! 台本で終了を決める刻みで`終了する`になり、その1つ前の刻みでは`続ける`であること。
//! 平坦な高さ場を据えるのは、高さ場を持たない世界では移動の掃引が評価できない領域で止まり位置が動かないためである。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」。

#![allow(clippy::unwrap_used)]

use blitz_engine::height_field::{高さ場, 高さ場の読み口, 高さ場諸元};
use blitz_game::{ゲームの進行段階, 確定済みの操作入力};
use blitz_math::{メートル, ラジアン, 大域メートル};

use super::contract::{ゲーム用高さ場, 刻み入力, 刻み結果, 読込済みチャンクの形の出どころ};
use super::game::終了を決める刻みの番号;
use super::世界実行;
use crate::app::固定刻みの番号;
use crate::cli::{ゲーム操作の出どころ, 起動モード, 遊ぶゲームの指定};
use crate::input::刻みごとの操作入力;

fn 平坦な高さ場を作る() -> 高さ場 {
    let 諸元 = 高さ場諸元::生成する(大域メートル::生成する(-100.0), 大域メートル::生成する(-100.0), メートル::生成する(100.0), 3, 3).unwrap();
    高さ場::生成する(諸元, vec![メートル::生成する(0.0); 9]).unwrap()
}

// 世界実行を丸ごと受ける自由関数を置かないため、刻み入力の生成と入口の呼び出しは各検査に書く。
/// 反証: 処理位置の並びで操作入力の適用と操作で決まる状態遷移と意図の生成とこの刻みで規則が行うことの決定を入れ替えると、決定の刻みは遷移前のタイトル表示中で移動の有無が決まり、
/// 場所巡り中へ入りながら同じ刻みでは位置が動かない。
#[test]
fn 決定と前進を同時に含む刻みは場所巡り中へ入りながら同じ刻みのうちに位置が動く() {
    let mut 世界実行 = 世界実行::起動設定から作る(遊ぶゲームの指定::キツネの場所巡り(ゲーム操作の出どころ::実行時の入力), 起動モード::無期限実行);
    世界実行.高さ場を据える(ゲーム用高さ場::読み込んだ(高さ場の読み口::高さ場を持つ世界(平坦な高さ場を作る())));
    let 出発地点 = 世界実行.刻み境界で確定したプレイヤーの大域位置().unwrap();
    let 決定と前進 = 確定済みの操作入力 {
        決定操作を押した瞬間か: true,
        前へ進む操作を押しているか: true,
        ..確定済みの操作入力::無操作()
    };
    let mut 器 = 刻みごとの操作入力::一描画の確定から生成する(決定と前進, ラジアン::生成する(0.0));
    let 入力 = 刻み入力::配る器から次の刻みぶんを生成する(&mut 器, 読込済みチャンクの形の出どころ::ストリーミングを使わない起動, 固定刻みの番号::起動時の最初());
    let 結果 = 世界実行.一刻み進める(入力, super::ゲーム更新の一刻みの秒()).unwrap();
    assert_eq!(結果, 刻み結果::続ける);
    let 表示内容 = 世界実行.この描画の描画供給を作る().画面へ重ねる表示内容.unwrap();
    assert_eq!(表示内容.進行段階, ゲームの進行段階::場所巡り中);
    assert!(世界実行.刻み境界で確定したプレイヤーの大域位置().unwrap().z() < 出発地点.z(), "検査の前提: 前へ進む操作で北(Zの負の向き)へ進む");
}

/// 反証: 刻み結果を`終了が決まったか`から組まず`続ける`に固定すると、終了を決めた刻みでイベントループが閉じない。
#[test]
fn 台本で終了を決める刻みの刻み結果は終了するでありその1つ前の刻みは続けるである() {
    let mut 世界実行 = 世界実行::起動設定から作る(遊ぶゲームの指定::キツネの場所巡り(ゲーム操作の出どころ::決定的な台本), 起動モード::スモーク実行 { 描画機会の数: 1 });
    let mut 器 = 刻みごとの操作入力::一描画の確定から生成する(確定済みの操作入力::無操作(), ラジアン::生成する(0.0));
    let mut 番号 = 固定刻みの番号::起動時の最初();
    let mut 一つ前の結果 = 刻み結果::続ける;
    loop {
        let 入力 = 刻み入力::配る器から次の刻みぶんを生成する(&mut 器, 読込済みチャンクの形の出どころ::ストリーミングを使わない起動, 番号);
        let 結果 = 世界実行.一刻み進める(入力, super::ゲーム更新の一刻みの秒()).unwrap();
        if 番号 == 終了を決める刻みの番号 {
            assert_eq!(一つ前の結果, 刻み結果::続ける, "終了を決める刻みの1つ前");
            assert_eq!(結果, 刻み結果::終了する, "終了を決める刻み");
            return;
        }
        assert_eq!(結果, 刻み結果::続ける, "終了を決める刻みより前の刻み");
        一つ前の結果 = 結果;
        番号 = 番号.本数だけ後の番号(1);
    }
}
