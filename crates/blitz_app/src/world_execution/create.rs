//! 世界実行を起動設定から組み立てる局面。呼ばれるのは起動時の1回だけであり、毎描画の入口とは呼び出し頻度が違う。
//! 共有される状態の初期値をここが決め、ゲーム固有の状態の初期値はゲーム配線が決める。

use blitz_engine::height_field::高さ場の読み口;

use super::camera_wiring::プレイヤーカメラの配線;
use super::game::ゲーム配線;
use super::movement_record::移動の観測の記録;
use super::世界実行;
use crate::cli::{起動モード, 遊ぶゲームの指定};
use crate::input::ゲーム操作の適用の方式;

impl 世界実行 {
    /// 実際の高さ場はカタログを構築した後に据える。カタログの構築はウィンドウとレンダラーの生成と同じ局面にあり、
    /// この組み立ての時点では読めない。据わるまでに描画は1つも走らない。
    pub(crate) fn 起動設定から作る(遊ぶゲーム: 遊ぶゲームの指定, モード: 起動モード) -> Self {
        let ゲーム配線 = ゲーム配線::起動設定から作る(遊ぶゲーム);
        let 操作の適用の方式 = ゲーム操作の適用の方式::起動モードから決める(モード);
        Self {
            台帳: ゲーム配線.開始時の台帳を作る(),
            ゲーム配線,
            操作の適用の方式,
            高さ場の読み口: 高さ場の読み口::高さ場を持たない世界,
            カメラ: プレイヤーカメラの配線::プレイヤー用で生成する(操作の適用の方式),
            移動の記録: 移動の観測の記録::まだ刻んでいない記録を作る(),
        }
    }
}
