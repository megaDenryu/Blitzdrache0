//! 遊ばない起動の世界実行が、刻み・カメラ・高さ場のどれにも踏み込まないことの検証。
//! 見るのは4つである。注視点を答えないこと、進行の要約を作らないこと、カタログを読まずに遊ばない世界の高さ場を返すこと、
//! 描画機会の更新がカメラを触らないことである。対照として、キツネの場所巡りの起動が注視点を答えることを見る。
//! 高さ場を読む検査が空のカタログを渡すのは、カタログを読む経路へ入れば未登録のアセットとして必ず失敗し、
//! 読まずに返したことが答えの側から反証できるためである。
//! 実画面もレンダラーも使わず、起動設定から作った世界実行だけで組む。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断12」。

use blitz_engine::カタログ;
use blitz_math::{メートル, 大域メートル, 大域ワールド位置, 秒};

use super::contract::{この描画のカメラの入力, ゲーム用高さ場, 表示距離の指示, 読込済みチャンクの形の出どころ};
use super::世界実行;
use crate::app::{固定刻みの番号, 描画補間の割合};
use crate::cli::{ゲーム操作の出どころ, 起動モード, 遊ぶゲームの指定};

fn 遊ばない起動の世界実行() -> 世界実行 {
    世界実行::起動設定から作る(遊ぶゲームの指定::ゲームを遊ばない, 起動モード::無期限実行)
}

fn キツネの場所巡りの世界実行() -> 世界実行 {
    世界実行::起動設定から作る(遊ぶゲームの指定::キツネの場所巡り(ゲーム操作の出どころ::実行時の入力), 起動モード::無期限実行)
}

fn この描画のカメラの入力を作る() -> この描画のカメラの入力 {
    この描画のカメラの入力 {
        注視点: 大域ワールド位置::原点(),
        理想視点: 大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(0.0), 大域メートル::生成する(5.0)),
        理想距離: メートル::生成する(5.0),
        表示距離の下限: メートル::生成する(0.5),
        進めた時間: 秒::生成する(1.0 / 60.0),
    }
}

fn 現在の確定値そのものの割合() -> 描画補間の割合 {
    描画補間の割合::前の確定値から進んだ割合として作る(1.0)
}

/// 反証: 遊ばない起動が注視点を答えると、エンジンのカメラの姿勢がプレイヤーを持たない世界の台帳の値で上書きされる。
#[test]
fn 遊ばない起動はカメラの注視点を答えない() {
    let 世界実行 = 遊ばない起動の世界実行();
    assert!(世界実行.カメラの注視点にする混ぜた大域位置(現在の確定値そのものの割合()).is_none());
}

#[test]
fn 遊ばない起動は進行の要約を作らない() {
    let 世界実行 = 遊ばない起動の世界実行();
    assert!(世界実行.進行の要約を作る(固定刻みの番号::起動時の最初()).is_none());
}

/// 反証: 遊ばない起動がカタログを読むと、高さ場を持たない既存の検収の世界がどれも起動の途中で失敗する。
#[test]
fn 遊ばない起動はカタログを読まずに遊ばない世界の高さ場を返す() {
    let 世界実行 = 遊ばない起動の世界実行();
    let 結果 = 世界実行.カタログから高さ場を読み込む(&カタログ::空を作る());
    let Ok(高さ場) = 結果 else {
        panic!("遊ばない起動が空のカタログを読みに行った");
    };
    assert!(matches!(高さ場, ゲーム用高さ場::遊ばない世界));
}

/// 反証: 遊ばない起動が表示距離を据えると、ゲームを1つも回さない起動でカメラの距離が遮蔽の判定に従って動く。
#[test]
fn 遊ばない起動の描画機会の更新はカメラを触らない() {
    let mut 世界実行 = 遊ばない起動の世界実行();
    let 結果 = 世界実行.この描画の世界を描画機会の時間意味で更新する(現在の確定値そのものの割合(), 読込済みチャンクの形の出どころ::ストリーミングを使わない起動, この描画のカメラの入力を作る());
    let Ok(指示) = 結果 else {
        panic!("遊ばない起動が世界の形を尋ねる口を組んだ");
    };
    assert!(matches!(指示, 表示距離の指示::カメラを触らない));
}

/// 対照: 同じ口が、プレイヤーを持つ起動では注視点を答える。答えない側だけを見ると、口そのものが常に答えない実装でも通る。
#[test]
fn キツネの場所巡りの起動はカメラの注視点を答える() {
    let 世界実行 = キツネの場所巡りの世界実行();
    assert!(世界実行.カメラの注視点にする混ぜた大域位置(現在の確定値そのものの割合()).is_some());
}
