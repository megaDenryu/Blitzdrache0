//! 刻み入力: 世界実行の固定刻みの入口が1刻みぶん受け取る値。確定済みの操作入力・前へ進む向きの方位角・
//! 読込済みチャンクの形の出どころ・固定刻みの番号を持ち、描画補間の割合を持たない。番号を載せるのは、決定的な台本が
//! その刻みの操作を番号から決めるためであり、番号の所有者は時間進行配線である(参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」)。持たないことが、描画の値を固定刻みへ戻さないという
//! 不変条件の型による表現である(参照: `_doc/設計/時間の規律.md`「判断6」)。
//!
//! カメラのヨーを前へ進む向きの方位角へ写すのはこの型の生成であり、ゲームロジック層はカメラの型を1つも知らない。
//! 注意: ヨーは、その描画のカメラ操作を反映する前に読んだ値でなければならない。この読む地点の順序を守るのは`app/frame.rs`と
//! `app/frame/game_steps.rs`の工程の並びであり、この型も試験も守っていない。この型が保つのは、生成のときに受け取ったヨーを
//! 保持し、生成の後にカメラが動いても読み直さないことまでである(参照: `_doc/設計/時間の規律.md`「入力の規律」)。

use blitz_game::{前へ進む向きの方位角, 確定済みの操作入力};
use blitz_math::ラジアン;

use super::読込済みチャンクの形の出どころ;
use crate::app::固定刻みの番号;

pub(crate) struct 刻み入力<'世界> {
    操作入力: 確定済みの操作入力,
    前へ進む向き: 前へ進む向きの方位角,
    出どころ: 読込済みチャンクの形の出どころ<'世界>,
    番号: 固定刻みの番号,
}

impl<'世界> 刻み入力<'世界> {
    pub(crate) fn カメラのヨーから生成する(操作入力: 確定済みの操作入力, カメラのヨー: ラジアン, 出どころ: 読込済みチャンクの形の出どころ<'世界>, 番号: 固定刻みの番号) -> Self {
        Self {
            操作入力,
            前へ進む向き: 前へ進む向きの方位角::生成する(カメラのヨー),
            出どころ,
            番号,
        }
    }

    pub(in crate::world_execution) fn 操作入力(&self) -> 確定済みの操作入力 {
        self.操作入力
    }

    pub(in crate::world_execution) fn 前へ進む向きの方位角(&self) -> 前へ進む向きの方位角 {
        self.前へ進む向き
    }

    pub(in crate::world_execution) fn 出どころ(&self) -> 読込済みチャンクの形の出どころ<'世界> {
        self.出どころ
    }

    pub(in crate::world_execution) fn 固定刻みの番号(&self) -> 固定刻みの番号 {
        self.番号
    }
}
