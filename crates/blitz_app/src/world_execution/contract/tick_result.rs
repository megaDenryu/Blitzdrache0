//! 刻み結果: 世界実行が1刻み進めた結果として返す判別共用体。ゲームの終了要求を持ち、世界の内部の終了を外から覗かせずに型で返す。
//! イベントループを閉じるかどうかは`アプリ`がこの値だけで決める。

/// 1刻み進めた結果、イベントループを閉じるべきかどうか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 刻み結果 {
    続ける,
    終了する,
}

impl 刻み結果 {
    /// 刻みの確定の処理位置が、この刻みまでに終了が決まったかから組む。
    pub(in crate::world_execution) fn 終了が決まったかから組む(終了が決まったか: bool) -> Self {
        if 終了が決まったか { Self::終了する } else { Self::続ける }
    }
}
