//! 描画供給: 世界実行の描画機会の抽出の入口が1描画に1度作る、借用を持たない値。画面へ重ねる表示内容と、移動とカメラの計器を持つ。
//! 動く個体の大域の位置と向きの指定一覧は毎描画のヒープ確保を避けるため描画供給に含めず、世界実行が所有で預けて戻す。
