//! 2つを1つの値で作ると計器が1描画古い値になる(参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断12」)。

use super::移動とカメラの計器;
use crate::overlay_ui::ゲーム画面の表示内容;

pub(crate) struct 描画供給 {
    pub(crate) 画面へ重ねる表示内容: Option<ゲーム画面の表示内容>, // 遊ばない起動と歩くだけでは無く、eguiはゲームの画面を1つも描かない
    pub(crate) 移動とカメラの計器: Option<移動とカメラの計器>,     // 遊ばない起動では無く、開発用UIは計器の面を描かない
}
