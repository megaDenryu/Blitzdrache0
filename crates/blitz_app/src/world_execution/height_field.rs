//! 世界実行の起動時と必要時の入口。カタログから高さ場を読むこと、読んだ高さ場を据えること、束の読込より前に動く個体を
//! 宣言することを持つ。呼ばれるのはカタログを構築した起動時と、実行時アセット一式の差し替え(ホットリロード)である。
//!
//! 読むことと据えることを分けるのは、反映の準備が状態を1つも変えずに失敗しうる工程を全部終えてから据えるためである
//! (参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断11」の`資源の配線`)。

use blitz_engine::height_field::{高さ場の読み口, 高さ場読込エラー};
use blitz_render::{レンダラーエラー, 描画シーン素材, 描画束ID};

use super::contract::ゲーム用高さ場;
use super::世界実行;

impl 世界実行 {
    /// 遊ばない起動ではカタログを読まない。既存の検収の世界のカタログは高さ場を持たず、遊ばない起動は高さを1度も参照しない。
    pub(crate) fn カタログから高さ場を読み込む(&self, カタログ: &blitz_engine::カタログ) -> Result<ゲーム用高さ場, 高さ場読込エラー> {
        if !self.ゲーム配線.ゲームを遊ぶか() {
            return Ok(ゲーム用高さ場::遊ばない世界);
        }
        Ok(ゲーム用高さ場::読み込んだ(高さ場の読み口::カタログから読み込む(カタログ)?))
    }

    /// 読み口を据え、その高さ場の地表へゲームの足元と目的地を置き直す。2つを1つの操作にするのは、読み口だけを差し替えて
    /// 置き直し忘れると、柱の真下で到達が成立しない状態が黙って作られるためである。
    pub(crate) fn 高さ場を据える(&mut self, 高さ場: ゲーム用高さ場) {
        let ゲーム用高さ場::読み込んだ(読み口) = 高さ場 else {
            return;
        };
        self.ゲーム配線.高さ場の地表へ足元と目的地を置き直す(&読み口, &mut self.台帳);
        self.高さ場の読み口 = 読み口;
    }

    /// 束の読込より前に、その束の描画シーン素材へ動く個体を宣言する。遊ばない起動の台帳は動く個体を1体も持たないため1件も宣言せず、
    /// 全描画対象が読込時に一度だけ書く静的な個体変換のままになる。
    pub(crate) fn 動く個体を描画束へ宣言する(&self, 束id: 描画束ID, 描画シーン: &mut 描画シーン素材) -> Result<(), レンダラーエラー> {
        for 宣言 in self.台帳.束の動く個体の宣言一覧を作る(束id) {
            描画シーン.動く個体を宣言する(宣言)?;
        }
        Ok(())
    }
}
