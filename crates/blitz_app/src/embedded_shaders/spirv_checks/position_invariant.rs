//! シーンの頂点段が実際にGPUへ渡す最終SPIR-Vで、位置の組み込み出力の変数へ不変装飾(Invariant)が付いていることの検査。
//!
//! ソースの表記を証拠にしないのは、slangc 2025.11がどの書き方でもこの装飾を出さないためである(実測。詳細は
//! `crates/blitz_render/src/shader_set/position_invariant.rs`)。装飾はエンジン側の生成物加工が付けるため、加工が効いていることを
//! 生成物の語の並びから確かめなければ、深度プリパスと色パスが同じ位置を出す根拠が1つも残らない。
//!
//! 検査が装飾の対象idまで見るのは、装飾が並びのどこかに在るだけでは足りないためである。別の変数へ付いた装飾は、
//! 色パスの深度比較を等値にする条件を1つも満たさない。

use blitz_render::位置の不変装飾を付ける;

use super::super::scene_shaders::頂点SPIRV;
use super::spirv_module::{位置の組み込み出力のidを引く, 命令へ読み解く, 装飾の付いたidを集める};

/// SPIR-Vの装飾Invariantの値。
const 装飾_INVARIANT: u32 = 18;

#[test]
fn 埋め込みの頂点段は加工前に不変装飾を持たない() {
    let 命令一覧 = match 命令へ読み解く(頂点SPIRV) {
        Ok(一覧) => 一覧,
        Err(誤り) => panic!("埋め込みの頂点段のSPIR-Vを読めない: {誤り}"),
    };
    let 位置のid = match 位置の組み込み出力のidを引く(&命令一覧) {
        Ok(id) => id,
        Err(誤り) => panic!("{誤り}"),
    };
    assert!(
        !装飾の付いたidを集める(&命令一覧, 装飾_INVARIANT).contains(&位置のid),
        "slangcが不変装飾を出すようになった。生成物への加工が不要になったかを見直すこと"
    );
}

#[test]
fn 描画へ渡す頂点段の位置の変数へ不変装飾が付いている() {
    let 加工済み = match 位置の不変装飾を付ける(頂点SPIRV) {
        Ok(バイト列) => バイト列,
        Err(誤り) => panic!("埋め込みの頂点段へ不変装飾を付けられない: {誤り}"),
    };
    let 命令一覧 = match 命令へ読み解く(&加工済み) {
        Ok(一覧) => 一覧,
        Err(誤り) => panic!("加工済みの頂点段のSPIR-Vを読めない: {誤り}"),
    };
    let 位置のid = match 位置の組み込み出力のidを引く(&命令一覧) {
        Ok(id) => id,
        Err(誤り) => panic!("{誤り}"),
    };
    assert!(
        装飾の付いたidを集める(&命令一覧, 装飾_INVARIANT).contains(&位置のid),
        "位置の組み込み出力(id{位置のid})へ不変装飾が付いていない"
    );
}
