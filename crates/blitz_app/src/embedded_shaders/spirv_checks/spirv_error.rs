//! シェーダー中間表現の読み解きが途中で止まる原因。検査は起動を止めないため起動エラーへは合流させず、
//! 検査の中で閉じる。

use thiserror::Error;

/// シェーダー中間表現(SPIR-V)を命令の並びへ読み解く途中で見つかった破れ。
#[derive(Debug, Error)]
pub(super) enum シェーダー中間表現の読み解きエラー {
    #[error("SPIR-Vのバイト長が語の並びとして読めない: {バイト長}")]
    語の並びとして読めないバイト長 { バイト長: usize },

    #[error("SPIR-Vの魔法数が合わない: {実測:#x}")]
    魔法数が合わない { 実測: u32 },

    #[error("SPIR-Vに{名前}という名前の宣言が無い")]
    名前の宣言が無い { 名前: String },

    #[error("SPIR-Vに位置の組み込み出力の宣言が無い")]
    位置の組み込み出力の宣言が無い,
}
