//! 布のXPBDの参照比較(Issue #36「検証」): GPUで進めた布と同じ初期条件・同じ刻み数・同じ反復回数でCPUの参照計算を回し、
//! 終了時の読み戻しと突き合わせる材料。担当するのは、題材を持つことと、その描画で進めた刻みの本数を数えることである。
//! 突き合わせの行の綴りは`reports::cloth_xpbd_reference`が持つ。

use blitz_sim::constraint_graph::目標拘束のバッチ;
use blitz_sim::{刻み幅, 布の参照計算, 布の参照計算の条件, 布の参照計算エラー, 布の彩色済み拘束};

use super::time_step::進める刻み数;

/// 参照比較の題材。GPUの布素材と同じ布データ・物性から作った彩色済み拘束と目標拘束のバッチと、GPUの定数と同じ値の条件を持つ。
pub(crate) struct 参照比較の題材 {
    pub(crate) 拘束: 布の彩色済み拘束,
    pub(crate) 目標拘束: 目標拘束のバッチ,
    pub(crate) 条件: 布の参照計算の条件,
    pub(crate) 反復回数: u32,
    pub(crate) コンプライアンス: f32, // 報告に書く値。構造とせん断へ同じ値を与えている
    pub(crate) 一辺粒子数: u32,
}

pub(crate) struct 布の参照比較 {
    題材: 参照比較の題材,
    進めた刻み数: u32, // 起動からGPUの布が進めた固定刻みの本数。参照計算を同じ本数だけ回す
}

impl 布の参照比較 {
    pub(crate) fn 始める(題材: 参照比較の題材) -> Self {
        Self {
            題材, 進めた刻み数: 0
        }
    }

    /// その描画でGPUの布へ渡した刻み数を足す。刻み0本の描画では何も変わらない。
    pub(crate) fn 刻みを数える(&mut self, 刻み数: 進める刻み数) {
        self.進めた刻み数 += u32::from(刻み数.本数());
    }

    pub(crate) fn 題材(&self) -> &参照比較の題材 {
        &self.題材
    }

    pub(crate) fn 進めた刻み数(&self) -> u32 {
        self.進めた刻み数
    }

    /// GPUが進めたのと同じ刻み数・同じ反復回数で参照計算を回す。
    pub(crate) fn 参照計算を回す(&self) -> Result<布の参照計算, 布の参照計算エラー> {
        self.題材.回す(self.題材.条件, self.題材.反復回数, self.進めた刻み数)
    }
}

impl 参照比較の題材 {
    /// 条件・反復回数・刻み数を差し替えて参照計算を回す。硬さの記録(反復回数と刻み幅を変えたときの垂れ)がこれを使う。
    pub(crate) fn 回す(
        &self, 条件: 布の参照計算の条件, 反復回数: u32, 刻み数: u32
    ) -> Result<布の参照計算, 布の参照計算エラー> {
        let mut 参照 = 布の参照計算::生成する(&self.拘束, &self.目標拘束, 条件)?;
        for _ in 0..刻み数 {
            参照.一刻み進める(反復回数);
        }
        Ok(参照)
    }

    /// 刻み幅だけを差し替えた条件。dtを変えたときの挙動を同じ経過時間で比べるときに使う。
    pub(crate) fn 刻み幅を変えた条件(&self, 刻み幅: 刻み幅) -> 布の参照計算の条件 {
        布の参照計算の条件 { 刻み幅, ..self.条件 }
    }
}
