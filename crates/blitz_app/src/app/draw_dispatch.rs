//! スモークアクションに応じた描画呼び出しの振り分け(通常描画/読み戻し判定)と、そのフレームの材料から描画入力を組み立てて実行する入口。
//! 入口を1つ置くのは、地形詳細段選択と可視個体選択の受け皿がアプリの外へ預けられている間だけ描画入力を作れるためであり、
//! 呼び出し元は預けと戻しだけを見ればよい。

mod pixel_readback;
mod rewrite_action;

use blitz_render::frame_input::プリミティブ発行受け皿;
use blitz_render::{UI描画データ, フレーム描画入力, 布フレーム入力, 読み戻し結果};

use super::visibility::可視選択受け皿;
use super::アプリ;
use crate::error::起動エラー;
use crate::smoke::{self, スモークアクション};

/// 1フレームの描画に要る、アプリの外へ預けてある値と組み立て済みの値の束。
pub(super) struct フレーム材料<'a> {
    pub(super) アクション: スモークアクション,
    pub(super) 視点情報: &'a super::frame::フレーム視点,
    pub(super) 地形詳細段選択一覧: &'a [blitz_render::地形詳細段選択],
    pub(super) 可視受け皿: &'a 可視選択受け皿,
    pub(super) プリミティブ発行: &'a プリミティブ発行受け皿,
    pub(super) 布入力: Option<布フレーム入力>,
    pub(super) ui描画: Option<UI描画データ>,
}

impl アプリ {
    pub(super) fn 描画まで進める(&mut self, 材料: フレーム材料<'_>) -> Result<(), 起動エラー> {
        let 可視個体選択一覧 =
            blitz_render::可視個体選択一覧::生成する(材料.可視受け皿.選択一覧(), 材料.可視受け皿.id列(), 材料.可視受け皿.段範囲列())?;
        // 焼き直しの判定は前回焼いた鍵を書き換えるため、借用が重ならないよう描画入力の組み立てより前に済ませる。
        let 焼き上げ入力 = self.天空.焼き上げ入力(材料.視点情報);
        let mut 描画入力 = super::frame::描画入力を組み立てる(
            self,
            焼き上げ入力,
            材料.視点情報,
            材料.地形詳細段選択一覧,
            可視個体選択一覧,
            材料.プリミティブ発行,
        );
        描画入力.布 = 材料.布入力;
        描画入力.ui描画 = 材料.ui描画;
        if self.ダンプ対象フレームか(材料.アクション) {
            self.読み戻してダンプする(描画入力, 材料.視点情報, 材料.アクション)
        } else {
            self.実行して判定する(材料.アクション, 描画入力)
        }
    }
}

impl アプリ {
    pub(super) fn 実行して判定する(
        &mut self, アクション: スモークアクション, 描画入力: フレーム描画入力<'_>
    ) -> Result<(), 起動エラー> {
        rewrite_action::適用する(self, アクション)?;

        let Some(レンダラー) = &mut self.レンダラー else {
            return Ok(());
        };

        match アクション {
            スモークアクション::初期色判定
            | スモークアクション::アセット反映後判定
            | スモークアクション::最終判定
            | スモークアクション::ヘルメット判定
            | スモークアクション::粒子判定
            | スモークアクション::開発UI判定
            | スモークアクション::シャドウ判定
            | スモークアクション::複数描画対象判定 => pixel_readback::画素を判定する(レンダラー, 描画入力, アクション),
            // foxステージ(判断45): 基準フレームを保存し、後続フレームとの差分でアニメーションの動きを判定する。
            スモークアクション::フォックス基準保存 => match レンダラー.一フレーム描画して読み戻す(描画入力)? {
                読み戻し結果::読み戻した(画像) => {
                    self.スモーク基準画像 = Some(画像);
                    Ok(())
                }
                読み戻し結果::見送った(理由) => Err(起動エラー::ピクセル判定失敗(
                    format!("基準フレームで描画が見送られた: {理由:?}"),
                )),
            },
            スモークアクション::フォックス差分判定 => {
                let Some(基準) = &self.スモーク基準画像 else {
                    return Err(起動エラー::ピクセル判定失敗(
                        "差分判定前に基準画像が保存されていない".to_string(),
                    ));
                };
                match レンダラー.一フレーム描画して読み戻す(描画入力)? {
                    読み戻し結果::読み戻した(画像) => smoke::アニメーション差分を判定する(基準, &画像),
                    読み戻し結果::見送った(理由) => Err(起動エラー::ピクセル判定失敗(format!(
                        "差分判定フレームで描画が見送られた: {理由:?}"
                    ))),
                }
            }
            _ => {
                レンダラー.一フレーム描画する(描画入力)?;
                Ok(())
            }
        }
    }
}
