//! スモークアクションに応じた描画呼び出しの振り分け(通常描画/読み戻し判定)。

mod pixel_readback;
mod rewrite_action;

use blitz_render::{フレーム描画入力, 読み戻し結果};

use super::アプリ;
use crate::error::起動エラー;
use crate::smoke::{self, スモークアクション};

impl アプリ {
    pub(super) fn 実行して判定する(
        &mut self, アクション: スモークアクション, 描画入力: フレーム描画入力<'_>
    ) -> Result<(), 起動エラー> {
        rewrite_action::適用する(self, アクション)?;

        let Some(レンダラー) = &mut self.レンダラー else {
            return Ok(());
        };

        match アクション {
            スモークアクション::初期色判定
            | スモークアクション::アセット反映後判定
            | スモークアクション::最終判定
            | スモークアクション::ヘルメット判定
            | スモークアクション::粒子判定
            | スモークアクション::開発UI判定
            | スモークアクション::シャドウ判定
            | スモークアクション::複数描画対象判定 => pixel_readback::画素を判定する(レンダラー, 描画入力, アクション),
            // foxステージ(判断45): 基準フレームを保存し、後続フレームとの差分でアニメーションの動きを判定する。
            スモークアクション::フォックス基準保存 => match レンダラー.一フレーム描画して読み戻す(描画入力)? {
                読み戻し結果::読み戻した(画像) => {
                    self.スモーク基準画像 = Some(画像);
                    Ok(())
                }
                読み戻し結果::見送った(理由) => Err(起動エラー::ピクセル判定失敗(
                    format!("基準フレームで描画が見送られた: {理由:?}"),
                )),
            },
            スモークアクション::フォックス差分判定 => {
                let Some(基準) = &self.スモーク基準画像 else {
                    return Err(起動エラー::ピクセル判定失敗(
                        "差分判定前に基準画像が保存されていない".to_string(),
                    ));
                };
                match レンダラー.一フレーム描画して読み戻す(描画入力)? {
                    読み戻し結果::読み戻した(画像) => smoke::アニメーション差分を判定する(基準, &画像),
                    読み戻し結果::見送った(理由) => Err(起動エラー::ピクセル判定失敗(format!(
                        "差分判定フレームで描画が見送られた: {理由:?}"
                    ))),
                }
            }
            _ => {
                レンダラー.一フレーム描画する(描画入力)?;
                Ok(())
            }
        }
    }
}
