//! スモークアクションに応じた描画呼び出しの振り分け(通常描画/読み戻し判定)。

use blitz_render::{フレーム描画入力, 読み戻し結果};

use super::アプリ;
use crate::error::起動エラー;
use crate::smoke::{self, スモークアクション};

impl アプリ {
    pub(super) fn 実行して判定する(
        &mut self,
        アクション: スモークアクション,
        描画入力: フレーム描画入力,
    ) -> Result<(), 起動エラー> {
        match アクション {
            スモークアクション::シェーダー書き換え => smoke::シェーダーを書き換える(&self.シェーダー監視パス)?,
            スモークアクション::アセット書き換え => smoke::アセットを書き換える(&self.アセットルート)?,
            _ => {}
        }

        let Some(レンダラー) = &mut self.レンダラー else {
            return Ok(());
        };

        match アクション {
            スモークアクション::初期色判定
            | スモークアクション::アセット反映後判定
            | スモークアクション::最終判定
            | スモークアクション::ヘルメット判定
            | スモークアクション::粒子判定 => {
                match レンダラー.一フレーム描画して読み戻す(描画入力)? {
                    読み戻し結果::読み戻した(画像) => smoke::ピクセルを判定する(&画像, アクション),
                    読み戻し結果::見送った(理由) => Err(起動エラー::ピクセル判定失敗(format!(
                        "判定対象フレームで描画が見送られた: {理由:?}"
                    ))),
                }
            }
            _ => {
                レンダラー.一フレーム描画する(描画入力)?;
                Ok(())
            }
        }
    }
}
