//! 継ぎ目検査で描画を除外したチャンクについて、準備済みデータの取り出しとGPU転送完了の報告だけを担当する。

use blitz_engine::{ストリーミング調停, チャンク座標};

use crate::error::起動エラー;

pub(super) fn 描画せず転送を完了する(調停: &mut ストリーミング調停, 座標: チャンク座標) -> Result<(), 起動エラー> {
    let Some(_シーン) = 調停.gpu転送のためにシーンデータを取り出す(座標)? else {
        return Err(起動エラー::ストリーミング準備済みデータ不在(座標));
    };
    調停.gpu転送の完了を報告する(座標)?;
    Ok(())
}
