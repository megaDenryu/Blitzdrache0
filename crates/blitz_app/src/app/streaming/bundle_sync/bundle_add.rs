//! 準備の整ったチャンク1つを、レンダラーの描画束と描画束の台帳へ載せる工程。受け取るのは座標とその世界の大域ずらし量、
//! 返すのは載せた結果である。触れるのはこの1つの束だけであり、どの座標を載せるかの決定と解除の順序には触れない。
//!
//! 追加を親の適用の局面から分けるのは、追加が「1つの束をシーンから作る」工程であり、適用が「そのフレームの進行を
//! 追加と解除へ振り分ける」工程だからである。呼ばれるのも、準備完了の座標がある回だけである。

use blitz_engine::チャンク座標;
use blitz_math::大域ワールド位置;
use blitz_render::レンダラー;

use super::束idを作る;
use crate::app::draw_bundle_ledger::描画束の台帳;
use crate::app::streaming::ストリーミング配線;
use crate::error::起動エラー;

impl ストリーミング配線 {
    /// 描画対象数へ複製の指定を渡さないのは、複製配置がベンチ専用の機能でありチャンクの実体を歪めるためである。
    /// 描画の基準原点は変換境界がこの座標から導出する。座標を渡すことで、シーンの全描画対象がこの束に属することも同じ境界で検証される。
    pub(super) fn 描画束を追加する(&mut self, レンダラー: &mut レンダラー, 台帳: &mut 描画束の台帳, 座標: チャンク座標, 大域ずらし量: 大域ワールド位置) -> Result<(), 起動エラー> {
        let 束id = 束idを作る(座標)?;
        let Some(シーン) = self.調停.gpu転送のためにシーンデータを取り出す(座標)? else {
            return Err(起動エラー::ストリーミング準備済みデータ不在(座標));
        };
        let 描画入力 = {
            let 材料 = 台帳.シーンを写す材料を組む(大域ずらし量, Some(self.チャンク一辺));
            crate::app::scene_load::シーンをレンダラー入力に変換する(&シーン, crate::cli::描画対象の並べ方::そのまま読む(), 座標, 材料)?
        };
        レンダラー.描画束を追加する(束id, &描画入力.描画シーン)?;
        台帳.束を登録する(束id, 描画入力.登録一式);
        self.調停.gpu転送の完了を報告する(座標)?;
        Ok(())
    }
}
