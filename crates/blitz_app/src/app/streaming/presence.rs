//! ストリーミングの有無: 起動がチャンクのストリーミングを使うかどうかと、使うならその配線を所有する枝。
//! `--streaming`を指定しない起動は配線を持たず、裸の`Option`で持ち回るとその意味が呼び出し側の約束になるため、名前のある型で持つ。
//!
//! その描画の読込済みチャンクの形の出どころをここが組むのは、出どころが配線の調停の借用そのものであり、配線を持つのが
//! この型だからである。アプリが自分のメソッドで組むと`&self`全体の借用になり、出どころを持ったままゲーム配線を動かす
//! 刻みの工程が成り立たない。フィールドのメソッドなら借りるのはこの枝だけである。

use super::ストリーミング配線;
use crate::game::読込済みチャンクの形の出どころ;

pub(in crate::app) struct ストリーミングの有無(Option<ストリーミング配線>); // 値なしが使わない起動。枝の列挙にしないのは配線が大きく空の枝との差を検査が拒むため

impl ストリーミングの有無 {
    pub(in crate::app) fn 使わない起動() -> Self {
        Self(None)
    }

    pub(in crate::app) fn 配線から生成する(配線: ストリーミング配線) -> Self {
        Self(Some(配線))
    }

    pub(in crate::app) fn 配線を借りる(&self) -> Option<&ストリーミング配線> {
        self.0.as_ref()
    }

    pub(in crate::app) fn 配線を可変で借りる(&mut self) -> Option<&mut ストリーミング配線> {
        self.0.as_mut()
    }

    // その描画の読込済みチャンクの形の出どころ。刻みを回す工程とカメラの遮蔽の工程が同じ組み方を共有する。
    pub(in crate::app) fn 読込済みチャンクの形の出どころを組む(&self) -> 読込済みチャンクの形の出どころ<'_> {
        match &self.0 {
            None => 読込済みチャンクの形の出どころ::ストリーミングを使わない起動,
            Some(配線) => 読込済みチャンクの形の出どころ::ストリーミング調停(配線.調停()),
        }
    }
}
