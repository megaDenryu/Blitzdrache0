//! 必要チャンク集合の中心にするプレイヤーの大域位置をどこから取るかを所有する。カメラの視点・ゲームのプレイヤー・検収の固定経路のどれを使うかを、CLIの位置源の指定と遊ぶゲームから選ぶ。
//! 検収の固定経路の端点と速さは`integration_route`が持ち、ここはどれを使うかの選択と、そのフレームの位置の引き当てだけを行う。

use blitz_engine::{カメラ, 固定経路};
use blitz_math::大域ワールド位置;

use super::integration_route::{整定込みの経過, 統合経路の経過, 統合経路を作る};
use crate::cli::{ストリーミング起動設定, プレイヤー位置源, 遊ぶゲームの指定};
use crate::error::起動エラー;

/// 必要チャンク集合の中心にするプレイヤーの大域位置をどこから取るかの決定。
///
/// - `カメラ視点`: 世界の中に位置を持つ対象がカメラしか居ない起動、つまりゲームを1つも遊ばない起動だけが使う。
/// - `ゲームのプレイヤー位置`: カメラの視点位置と分ける理由は2つある。1つは、視点が注視点から距離ぶん離れて動き、引きの操作で世界の外へ出ると中心のチャンク座標が目録に無い場所になって、現存する地形が1枚も必要集合へ入らず全部消えることである。もう1つは、注視点が描画補間で混ぜた位置を追うため、そこから求まる視点位置を中心にすると、混ぜた値が常駐チャンクと高さ場を経て次のゲーム更新の入力へ回り込むことである(参照: `_doc/設計/時間の規律.md`「判断6」)。
/// - `インスタンス統合経路`: 静止で先読み、往復で境界を横断、ふたたび静止で整定、の3局面を1本の経路で表す。往復の後に始点へ戻して静止するのは、束の解除と再読込を経た終状態を、一度も解除していない静止だけの実行と同じ必要集合で突き合わせるためである。突き合わせる相手が別の位置にあると、残留の有無と必要集合の違いを区別できない。
pub(super) enum プレイヤー位置決定 {
    カメラ視点,
    ゲームのプレイヤー位置,
    固定経路(固定経路),
    統合Dod経路(固定経路),
    インスタンス統合経路(固定経路),
}

impl プレイヤー位置決定 {
    /// CLIが位置源を明示した実行はその指定が勝つ。指定の無い実行だけを遊ぶゲームで分けるのは、フレーム数の決まった検収が`--streaming-route`等で位置源を明示しており、そちらの読込順の再現性をゲームの有無で変えないためである。
    /// プレイヤーを持つゲームを1つ残らずプレイヤーの確定位置へ寄せるのは、混ぜた値の回り込みを枝の選択そのもので塞ぐためである。実行がフレーム数の決まった検収かどうかで分ける形にすると、補間が中立でない実行だけが回り込む穴が残る。
    pub(super) fn 構築する(
        起動設定: &ストリーミング起動設定, 遊ぶゲーム: 遊ぶゲームの指定
    ) -> Result<Self, 起動エラー> {
        match 起動設定.位置源 {
            プレイヤー位置源::カメラ視点 => Ok(match 遊ぶゲーム {
                遊ぶゲームの指定::歩くだけ | 遊ぶゲームの指定::キツネの場所巡り(_) => Self::ゲームのプレイヤー位置,
                遊ぶゲームの指定::ゲームを遊ばない => Self::カメラ視点,
            }),
            プレイヤー位置源::固定経路 => Ok(Self::固定経路(起動設定.固定経路.経路を作る()?)),
            プレイヤー位置源::Ow3Dod経路 => Ok(Self::統合Dod経路(統合経路を作る()?)),
            プレイヤー位置源::インスタンスストリーム経路 => Ok(Self::インスタンス統合経路(統合経路を作る()?)),
        }
    }

    /// プレイヤーの大域位置を受け取るのは、`ゲームのプレイヤー位置`の枝がそのフレームの値を要るためである。
    /// 枝がその値を要るのに供給が無い状態は配線の誤りであり、黙ってカメラ視点へ落とさず型付きエラーにする。
    pub(super) fn 位置を求める(
        &self,
        フレーム番号: u32,
        カメラ: &カメラ,
        プレイヤーの大域位置: Option<大域ワールド位置>,
    ) -> Result<大域ワールド位置, 起動エラー> {
        Ok(match self {
            Self::カメラ視点 => 大域ワールド位置::局所ワールド位置から生成する(カメラ.視点ワールド位置()),
            Self::ゲームのプレイヤー位置 => {
                プレイヤーの大域位置.ok_or(起動エラー::必要チャンク集合の中心にするプレイヤーの大域位置が未供給)?
            }
            Self::固定経路(経路) => 経路.位置を求める(フレーム番号),
            Self::統合Dod経路(経路) => 経路.位置を求める(統合経路の経過(フレーム番号)),
            Self::インスタンス統合経路(経路) => 経路.位置を求める(整定込みの経過(フレーム番号)),
        })
    }

    pub(super) fn lod位置を求める(&self, フレーム番号: u32) -> Option<大域ワールド位置> {
        match self {
            Self::統合Dod経路(経路) => Some(経路.位置を求める(統合経路の経過(フレーム番号))),
            Self::インスタンス統合経路(経路) => Some(経路.位置を求める(整定込みの経過(フレーム番号))),
            // 地形の詳細段は見え方で決まるため、ゲームのプレイヤー位置を中心にする実行でもカメラの視点位置から測る。
            Self::カメラ視点 | Self::ゲームのプレイヤー位置 | Self::固定経路(_) => None,
        }
    }
}
