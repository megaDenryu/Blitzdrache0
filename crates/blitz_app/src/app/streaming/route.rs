//! プレイヤーの大域位置をどこから取るかを所有する。カメラ視点をそのまま使うか、フレーム番号から決まる固定経路を使うかを選び、経路の端点と速さの定数を持つ。
//! 経路の値そのものはblitz_engineの`固定経路`が計算し、ここは検証用世界に合わせた定数の設定と選択だけを行う。

use blitz_engine::{カメラ, 固定経路};
use blitz_math::{大域メートル, 大域ワールド位置};

use crate::cli::{プレイヤー位置源, 固定経路起動設定};
use crate::error::起動エラー;

/// 1フレームあたりの移動量。一辺100メートルを20フレームでまたぐため、先読み半径1の必要集合は20フレームに1回入れ替わる。
/// これより速いと読込が追いつかず、遅いと同じ回数の入れ替わりを見るのに長い実行が要る。
const 一フレーム移動量メートル: f64 = 5.0;
const 統合DOD始点Xメートル: f64 = 50.0;
const 統合DOD終点Xメートル: f64 = 250.0;
const 統合DOD静止フレーム数: u32 = 120;

/// インスタンス統合経路が往路と復路に使うフレーム数。始点と終点の200メートルを1フレーム5メートルで進むため往路が40フレームであり、
/// `固定経路`の三角波は80フレームで始点へ戻る。この値を過ぎたら位置を始点へ留め、必要集合が変わらない整定の局面にする。
const インスタンス統合往復フレーム数: u32 = 80;

pub(super) enum プレイヤー位置決定 {
    カメラ視点,
    固定経路(固定経路),
    統合Dod経路(固定経路),
    /// 静止で先読み、往復で境界を横断、ふたたび静止で整定、の3局面を1本の経路で表す。
    /// 往復の後に始点へ戻して静止するのは、束の解除と再読込を経た終状態を、一度も解除していない静止だけの実行と
    /// 同じ必要集合で突き合わせるためである。突き合わせる相手が別の位置にあると、残留の有無と必要集合の違いを区別できない。
    インスタンス統合経路(固定経路),
}

impl プレイヤー位置決定 {
    pub(super) fn 構築する(位置源: プレイヤー位置源, 固定経路設定: 固定経路起動設定) -> Result<Self, 起動エラー> {
        match 位置源 {
            プレイヤー位置源::カメラ視点 => Ok(Self::カメラ視点),
            プレイヤー位置源::固定経路 => Ok(Self::固定経路(固定経路設定.経路を作る()?)),
            プレイヤー位置源::Ow3Dod経路 => Ok(Self::統合Dod経路(統合経路を作る()?)),
            プレイヤー位置源::インスタンスストリーム経路 => Ok(Self::インスタンス統合経路(統合経路を作る()?)),
        }
    }

    pub(super) fn 位置を求める(&self, フレーム番号: u32, カメラ: &カメラ) -> 大域ワールド位置 {
        match self {
            Self::カメラ視点 => 大域ワールド位置::局所ワールド位置から生成する(カメラ.視点ワールド位置()),
            Self::固定経路(経路) => 経路.位置を求める(フレーム番号),
            Self::統合Dod経路(経路) => 経路.位置を求める(統合経路の経過(フレーム番号)),
            Self::インスタンス統合経路(経路) => 経路.位置を求める(整定込みの経過(フレーム番号)),
        }
    }

    pub(super) fn lod位置を求める(&self, フレーム番号: u32) -> Option<大域ワールド位置> {
        match self {
            Self::統合Dod経路(経路) => Some(経路.位置を求める(統合経路の経過(フレーム番号))),
            Self::インスタンス統合経路(経路) => Some(経路.位置を求める(整定込みの経過(フレーム番号))),
            Self::カメラ視点 | Self::固定経路(_) => None,
        }
    }
}

fn 統合経路を作る() -> Result<固定経路, 起動エラー> {
    Ok(固定経路::生成する(
        経路端点(統合DOD始点Xメートル),
        経路端点(統合DOD終点Xメートル),
        大域メートル::生成する(一フレーム移動量メートル),
    )?)
}

/// 静止して先読みする局面のぶんだけ遅らせた経過フレーム。静止のあいだは経路の始点に留まる。
fn 統合経路の経過(フレーム番号: u32) -> u32 {
    フレーム番号.saturating_sub(統合DOD静止フレーム数)
}

/// 往復を終えたら経過を止め、以後は始点へ留める。三角波は往復フレーム数ちょうどで始点へ戻るため、頭打ちがそのまま整定になる。
fn 整定込みの経過(フレーム番号: u32) -> u32 {
    統合経路の経過(フレーム番号).min(インスタンス統合往復フレーム数)
}

fn 経路端点(xメートル: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(xメートル),
        大域メートル::生成する(0.0),
        大域メートル::生成する(0.0),
    )
}
