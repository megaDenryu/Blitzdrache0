//! 毎フレームのストリーミング進行局面。呼ばれるのはカメラ更新の直後の1フレームに1度であり、起動時の組み立てとは呼び出し頻度が違う。
//! 調停を進め、そのフレームの進行をレンダラーの描画束と可視判定の材料へ反映し、地形の詳細段を選び直すまでを順に行う。

use std::time::Instant;

use super::bundle_sync;
use crate::app::アプリ;
use crate::error::起動エラー;

impl アプリ {
    /// カメラ更新の直後に呼ぶ。既定の位置源はカメラの視点位置であり、必要集合の中心を確定した視点から決めるため、カメラより先に呼んではならない。
    pub(in crate::app) fn ストリーミングを進める(&mut self) -> Result<(), 起動エラー> {
        let 大域オフセット = self.大域オフセット;
        let Some(配線) = &mut self.ストリーミング else {
            return Ok(());
        };
        // レンダラーが揃う前は進めない。準備完了したCPUデータを載せる相手が居らず、調停の保管だけが増えるためである。
        let Some(レンダラー) = &mut self.レンダラー else {
            return Ok(());
        };
        let Some(カタログ) = self.ホットリローダー.カタログを参照する() else {
            return Err(起動エラー::ストリーミングカタログ未構築);
        };
        // 格子と必要集合はオフセットを加えない世界座標で決まるため、位置源へは大域オフセットを足さない。オフセットは描画アンカーとカメラだけへ効く。
        let 大域位置 = 配線.位置決定.位置を求める(self.現在フレーム, &self.カメラ);
        // 詳細段は見え方で決まるため、必要集合の中心でなくカメラの視点位置から測る。`--streaming-route`のときは2つが別の位置になる。
        // チャンクの大域包囲領域と比べる値であるため、格子と同じく大域オフセットを加えない座標で測る。
        let カメラ位置 = 配線
            .位置決定
            .lod位置を求める(self.現在フレーム)
            .unwrap_or_else(|| blitz_math::大域ワールド位置::局所ワールド位置から生成する(self.カメラ.視点ワールド位置()));
        // 計測区間は調停と描画束の追加解除の両方を含む。ストリーミングがメインスレッドを占める時間はこの合計である。
        let 開始 = Instant::now();
        let 進行 = 配線.調停.一フレーム進める(大域位置, カタログ)?;
        bundle_sync::適用する(
            &mut 配線.調停,
            レンダラー,
            &mut self.可視判定,
            &進行,
            &mut 配線.実破棄受け皿,
            大域オフセット,
            配線.描画除外座標,
        )?;
        // 束の追加と解除を反映した後に選ぶ。台帳の常駐とレンダラーの束が一致している時点でなければ、存在しない束の段を選ぶためである。
        配線.地形lod.選択を更新する(&配線.調停, カメラ位置)?;
        配線
            .計測
            .記録する(self.現在フレーム, 開始.elapsed(), &進行, 配線.地形lod.座標別の段を参照する());
        if 配線.報告する {
            crate::reports::streaming::進行を表示する(self.現在フレーム, &進行);
        }
        Ok(())
    }
}
