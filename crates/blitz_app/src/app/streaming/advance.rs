//! 毎フレームのストリーミング進行局面。呼ばれるのはカメラ更新の直後の1フレームに1度であり、起動時の組み立てとは呼び出し頻度が違う。
//! 位置を決め、ゲームが見る世界の形を変え、地形の詳細段を選び直し、計測するまでを順に行う。
//! 世界の形を変える部分だけを別の名前の命令にするのは、ゲームの次の刻みが見る形を決める工程が、IO・GPUの準備や計測と同じ名前の中に埋もれないためである。
//! その命令は1描画に1度、全刻みを回し終えた後・描画の前に呼ばれ、出どころが調停を共有借用で持つため1つの描画の全刻みは同じ版の形を見る。
//! ゲームから観測できる反映を固定刻みの工程境界へ置く作業は[Issue #146](https://github.com/megaDenryu/Blitzdrache0/issues/146)が持つ。
//! 参照: `_doc/設計/チャンクストリーミング.md`「刻みが見る世界の形の版」

use std::time::Instant;

use blitz_engine::ストリーミング進行;
use blitz_math::大域ワールド位置;
use blitz_render::レンダラー;

use super::ストリーミング配線;
use crate::app::draw_bundle_ledger::描画束の台帳;
use crate::error::起動エラー;

/// その描画のストリーミングを進めるために、配線の外から要る材料。6つは毎回そろって渡るため1つの値で持つ。
pub(in crate::app) struct ストリーミング進行の材料<'借用> {
    pub(in crate::app) レンダラー: &'借用 mut レンダラー,
    pub(in crate::app) 描画束の台帳: &'借用 mut 描画束の台帳,
    pub(in crate::app) カメラ: &'借用 blitz_engine::カメラ,
    pub(in crate::app) プレイヤーの大域位置: Option<大域ワールド位置>,
    pub(in crate::app) 大域ずらし量: 大域ワールド位置,
    pub(in crate::app) 現在フレーム: u32,
}

impl ストリーミング配線 {
    pub(in crate::app) fn この描画のストリーミングを進める(&mut self, カタログ: &blitz_engine::カタログ, 材料: ストリーミング進行の材料<'_>) -> Result<(), 起動エラー> {
        // 格子と必要集合はずらし量を加えない世界座標で決まるため、位置源へは大域ずらし量を足さない。ずらし量は描画の基準原点とカメラだけへ効く。
        let 大域位置 = self.位置決定.位置を求める(材料.現在フレーム, 材料.カメラ, 材料.プレイヤーの大域位置)?;
        // 詳細段は見え方で決まるため、必要集合の中心でなくカメラの視点位置から測る。`--streaming-route`のときは2つが別の位置になる。
        // チャンクの大域包囲領域と比べる値であるため、格子と同じく大域ずらし量を加えない座標で測る。
        let カメラ位置 = self.位置決定.lod位置を求める(材料.現在フレーム).unwrap_or_else(|| 大域ワールド位置::局所ワールド位置から生成する(材料.カメラ.視点ワールド位置()));
        // 計測区間は調停と描画束の追加解除の両方を含む。ストリーミングがメインスレッドを占める時間はこの合計である。
        let 開始 = Instant::now();
        let 進行 = self.ゲームが見る世界の形を変える(大域位置, カタログ, 材料.レンダラー, 材料.描画束の台帳, 材料.大域ずらし量)?;
        // 束の追加と解除を反映した後に選ぶ。台帳の常駐とレンダラーの束が一致している時点でなければ、存在しない束の段を選ぶためである。
        self.地形lod.選択を更新する(&self.調停, カメラ位置)?;
        self.計測.記録する(材料.現在フレーム, 開始.elapsed(), &進行, self.地形lod.座標別の段を参照する());
        if self.報告する {
            crate::reports::streaming::進行を表示する(材料.現在フレーム, &進行);
        }
        Ok(())
    }

    /// 調停を1フレーム進めて読込済みチャンクの形の集合を更新し、その進行をレンダラーの描画束と描画束の台帳へ反映する。
    /// 返す進行は、そのフレームで形が変わった座標(準備完了・CPUデータ破棄・解除待ち)を運ぶ。
    fn ゲームが見る世界の形を変える(
        &mut self,
        プレイヤーの大域位置: 大域ワールド位置,
        カタログ: &blitz_engine::カタログ,
        レンダラー: &mut レンダラー,
        台帳: &mut 描画束の台帳,
        大域ずらし量: 大域ワールド位置,
    ) -> Result<ストリーミング進行, 起動エラー> {
        let 進行 = self.調停.一フレーム進める(プレイヤーの大域位置, カタログ)?;
        self.フレームの進行を束へ適用する(レンダラー, 台帳, &進行, 大域ずらし量)?;
        Ok(進行)
    }
}
