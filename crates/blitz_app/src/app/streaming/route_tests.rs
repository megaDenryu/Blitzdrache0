//! 必要チャンク集合の中心を、遊ぶゲームと位置源の指定からどう選ぶかの契約。
//!
//! プレイヤーを持つゲームと、1人も持たない起動を対にして見る。片方だけでは「常にゲームのプレイヤーを使う」
//! 実装も「常にカメラ視点を使う」実装も通ってしまうためである。
//!
//! 中心とカメラの視点を離した状態で見るのは、実機で壊れた形がその2つのずれだからである。引きの操作で
//! 視点が世界の外へ出たとき、中心がカメラ視点のままだと現存する地形が1枚も必要集合へ入らない。
//! カメラの視点位置は描画補間で混ぜた注視点から求まるため、そこを中心にすると混ぜた値が常駐チャンクと
//! 高さ場を経て次のゲーム更新の入力へ回り込む(参照: `_doc/設計/時間の規律.md`「判断6」)。

use blitz_engine::カメラ;
use blitz_math::{大域メートル, 大域ワールド位置};

use super::route::プレイヤー位置決定;
use crate::cli::{ゲーム操作の出どころ, ストリーミング起動設定, プレイヤー位置源, 遊ぶゲームの指定};

/// 世界の内側にあるプレイヤーの立ち位置。既定のカメラの視点位置(原点から+Zへ3メートル)と離してあるため、
/// どちらを中心に選んだかが返り値で分かれる。
fn プレイヤーの大域位置() -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(700.0), 大域メートル::生成する(0.0), 大域メートル::生成する(700.0))
}

fn 位置源を据えた起動設定を作る(位置源: プレイヤー位置源) -> ストリーミング起動設定 {
    let mut 設定 = ストリーミング起動設定::既定値();
    設定.位置源 = 位置源;
    設定
}

fn 位置決定を構築する(位置源: プレイヤー位置源, 遊ぶゲーム: 遊ぶゲームの指定) -> プレイヤー位置決定 {
    match プレイヤー位置決定::構築する(&位置源を据えた起動設定を作る(位置源), 遊ぶゲーム) {
        Ok(決定) => 決定,
        Err(誤り) => panic!("位置決定を構築できない: {誤り}"),
    }
}

fn 中心を求める(位置源: プレイヤー位置源, 遊ぶゲーム: 遊ぶゲームの指定) -> 大域ワールド位置 {
    let 決定 = 位置決定を構築する(位置源, 遊ぶゲーム);
    match 決定.位置を求める(0, &カメラ::生成する(), Some(プレイヤーの大域位置())) {
        Ok(位置) => 位置,
        Err(誤り) => panic!("中心を求められない: {誤り}"),
    }
}

fn カメラの視点の大域位置() -> 大域ワールド位置 {
    大域ワールド位置::局所ワールド位置から生成する(カメラ::生成する().視点ワールド位置())
}

#[test]
fn 歩くだけの起動は中心にゲームのプレイヤーの大域位置を使う() {
    assert_eq!(
        中心を求める(プレイヤー位置源::カメラ視点, 遊ぶゲームの指定::歩くだけ),
        プレイヤーの大域位置()
    );
}

#[test]
fn ゲームを遊ばない起動は中心にカメラの視点位置を使う() {
    assert_eq!(
        中心を求める(プレイヤー位置源::カメラ視点, 遊ぶゲームの指定::ゲームを遊ばない),
        カメラの視点の大域位置()
    );
}

/// 反証: ここがカメラの視点位置に戻ると、描画補間で混ぜた注視点から求まる位置が必要集合の中心になり、
/// 常駐チャンクが決める高さ場を経て、描画のためだけに作った値が次のゲーム更新の入力へ回り込む。
#[test]
fn キツネの場所巡りの起動は中心にゲームのプレイヤーの大域位置を使う() {
    let 指定 = 遊ぶゲームの指定::キツネの場所巡り(ゲーム操作の出どころ::実行時の入力);
    let 中心 = 中心を求める(プレイヤー位置源::カメラ視点, 指定);
    assert_eq!(中心, プレイヤーの大域位置());
    assert_ne!(中心, カメラの視点の大域位置());
}

/// 位置源を明示した実行の中心は遊ぶゲームで変わらない。フレーム数の決まった検収の読込順の再現性がここで守られる。
#[test]
fn 位置源を明示した起動の中心は遊ぶゲームで変わらない() {
    let 遊ばない = 中心を求める(プレイヤー位置源::固定経路, 遊ぶゲームの指定::ゲームを遊ばない);
    let 歩くだけ = 中心を求める(プレイヤー位置源::固定経路, 遊ぶゲームの指定::歩くだけ);
    assert_eq!(遊ばない, 歩くだけ);
    assert_ne!(遊ばない, プレイヤーの大域位置());
}

/// ゲームのプレイヤーを中心にする配線で位置が届かないのは配線の誤りであり、黙ってカメラ視点へ落ちてはならない。
#[test]
fn ゲームが位置を供給しなければ型付きエラーになる() {
    let 決定 = 位置決定を構築する(プレイヤー位置源::カメラ視点, 遊ぶゲームの指定::歩くだけ);
    assert!(決定.位置を求める(0, &カメラ::生成する(), None).is_err());
}
