//! ストリーミング配線を組み立てる局面。呼ばれるのは起動時の1度だけであり、毎フレームの進行とは呼び出し頻度が異なる。
//! 格子の一辺・先読み半径・メモリ上限という世界の決め事をエンジン側の設定型へ写して渡す。

use blitz_engine::{ストリーミング調停, ストリーミング調停設定};

use super::ストリーミング配線;
use crate::error::起動エラー;

/// `--streaming`が無ければ`None`を返す。既存のスモークとベンチはチャンク世界を使わないため、既定では読込器のスレッドも起動しない。
/// 起動設定を丸ごと受け取るのは、ストリーミングの節・遊ぶゲーム・起動モード・アセットの置き場の4つを読むためである。どれを読むかをこの局面が持ち、呼び出し側に選ばせない。
pub(in crate::app) fn ストリーミング配線を構築する(
    起動設定: &crate::cli::起動設定,
) -> Result<Option<ストリーミング配線>, 起動エラー> {
    let ストリーミング設定 = &起動設定.ストリーミング;
    if !ストリーミング設定.有効 {
        return Ok(None);
    }
    let 目録 = crate::app::scene_load::チャンク目録を構築する(&起動設定.アセットの置き場)?;
    let チャンク一辺 = 目録.一辺();
    let 設定 = ストリーミング調停設定 {
        先読み半径: ストリーミング設定.先読み半径,
        上限: ストリーミング設定.上限,
        読込: ストリーミング設定.読込,
    };
    Ok(Some(ストリーミング配線 {
        調停: ストリーミング調停::起動する(設定, 目録)?,
        チャンク一辺,
        位置決定: super::route::プレイヤー位置決定::構築する(ストリーミング設定, 起動設定.遊ぶゲーム)?,
        計測: super::measurement::ストリーミング計測::生成する(起動設定.モード),
        上限: ストリーミング設定.上限,
        報告する: ストリーミング設定.報告する,
        描画除外座標: ストリーミング設定.lod継ぎ目検査.and_then(|検査| 検査.欠落座標),
        実破棄受け皿: Vec::new(),
        差し替え前の実破棄待ち束: Vec::new(),
        地形lod: super::lod_sync::地形LOD配線::生成する(チャンク一辺, ストリーミング設定.lod継ぎ目検査),
    }))
}
