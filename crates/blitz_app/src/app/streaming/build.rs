//! ストリーミング配線を組み立てる局面。呼ばれるのは起動時の1度だけであり、毎フレームの進行とは呼び出し頻度が異なる。
//! 格子の一辺・先読み半径・メモリ上限という世界の決め事をエンジン側の設定型へ写して渡す。

use blitz_engine::{ストリーミング調停, ストリーミング調停設定};

use super::{ストリーミング配線, 一辺メートル};
use crate::cli::{ストリーミング起動設定, 起動モード};
use crate::error::起動エラー;

/// `--streaming`が無ければ`None`を返す。既存のスモークとベンチはチャンク世界を使わないため、既定では読込器のスレッドも起動しない。
pub(in crate::app) fn 構築する(
    起動設定: &ストリーミング起動設定,
    モード: 起動モード,
    アセットルート: &std::path::Path,
) -> Result<Option<ストリーミング配線>, 起動エラー> {
    if !起動設定.有効 {
        return Ok(None);
    }
    let 目録 = crate::app::scene_load::チャンク目録を構築する(アセットルート)?;
    let 設定 = ストリーミング調停設定 {
        一辺: blitz_math::大域メートル::生成する(一辺メートル),
        先読み半径: 起動設定.先読み半径,
        上限: 起動設定.上限,
    };
    Ok(Some(ストリーミング配線 {
        調停: ストリーミング調停::起動する(設定, 目録)?,
        位置決定: super::route::プレイヤー位置決定::構築する(起動設定.位置源)?,
        計測: super::measurement::ストリーミング計測::生成する(モード),
        上限: 起動設定.上限,
        報告する: 起動設定.報告する,
        実破棄受け皿: Vec::new(),
        地形lod: super::lod_sync::地形LOD配線::生成する(起動設定.lod継ぎ目検査),
    }))
}
