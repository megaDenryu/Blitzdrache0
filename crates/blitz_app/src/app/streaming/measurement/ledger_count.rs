//! 台帳登録数の観測。担当するのは、毎フレームの台帳登録数から最大と最終の2つを保つことである。
//! 触れるのはこの2つのフィールドだけであり、最大は記録のたびに単調非減少、最終は最後に記録した値そのものになる。
//!
//! 最大だけを持たない理由は、最大が実行の途中のどこかで達した値であり終状態を表さないことにある。
//! 往復の終わりに不要な束が台帳へ残っていても、その実行の最大は静止だけの実行の最大と同じ値になりうる。

#[derive(Clone, Copy)]
pub(crate) struct 台帳登録数の観測 {
    最大: usize,
    最終: usize,
}

impl 台帳登録数の観測 {
    pub(super) fn 生成する() -> Self {
        Self { 最大: 0, 最終: 0 }
    }

    pub(super) fn 記録する(&mut self, 登録数: usize) {
        self.最大 = self.最大.max(登録数);
        self.最終 = 登録数;
    }

    pub(crate) fn 最大(self) -> usize {
        self.最大
    }

    /// 最後に記録したフレームの登録数。1フレームも記録していなければ0である。
    pub(crate) fn 最終(self) -> usize {
        self.最終
    }
}
