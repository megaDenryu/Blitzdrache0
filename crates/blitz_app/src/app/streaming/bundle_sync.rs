//! チャンク座標と描画束IDの対応規則を所有し、そのフレームの進行が挙げた座標へ束の追加と解除を適用する。
//! 台帳の段階順は調停が持ち、ここは調停とレンダラーのあいだで座標・束ID・描画シーン素材を受け渡すだけである。

mod transfer_without_draw;

use blitz_engine::{ストリーミング調停, ストリーミング進行, チャンク一辺, チャンク座標};
use blitz_render::{レンダラー, 描画束ID};

use crate::app::persistent_bundles::遠景の束ID;
use crate::app::scene_load::起動時シーンの束ID;
use crate::error::起動エラー;

use transfer_without_draw::描画せず転送を完了する;

/// チャンク座標の永続化番号が持つXとZの符号ビット。排他的論理和を取ると座標空間の原点が識別空間の中央へ移る。
pub(super) const 座標番号の符号ビット: u64 = 0x8000_0000_8000_0000;

/// 座標そのものがチャンクの識別子であるため、束IDは座標の番号から純粋に決める。対応表を別に持つと同じ識別が2箇所で管理される。
/// 起動時のシーンは束ID0を占め続ける(レンダラーはシャドウ描画入力が1件以上であることを不変条件にしており、チャンクが1つも常駐しない期間でも描画対象が要る)。
/// そのため座標番号をそのまま使えない。原点チャンクの番号が0であり衝突するためである。原点を識別空間の中央へ移すと、0へ写る座標は世界の隅である(x=i32::MIN, z=i32::MIN)だけになる。
pub(super) fn 束idを作る(座標: チャンク座標) -> Result<描画束ID, 起動エラー> {
    let 番号 = 座標.番号を返す() ^ 座標番号の符号ビット;
    if 番号 == 起動時シーンの束ID.番号を返す() || 番号 == 遠景の束ID.番号を返す() {
        return Err(起動エラー::ストリーミング束ID衝突(座標));
    }
    Ok(描画束ID::生成する(番号))
}

/// 束IDから座標を復元する。符号ビットとの排他的論理和は自身が逆写像(合成すると恒等)であるため、対応表なしで戻せる。
fn 束idから座標を復元する(束id: 描画束ID) -> チャンク座標 {
    チャンク座標::番号から復元する(束id.番号を返す() ^ 座標番号の符号ビット)
}

/// レンダラーの描画束・可視判定の材料・プリミティブ描画項目は同じ束IDで対になるため、追加も解除も同じ走査で3つへ反映する。
#[allow(clippy::too_many_arguments)]
pub(super) fn 適用する(
    調停: &mut ストリーミング調停,
    レンダラー: &mut レンダラー,
    可視判定: &mut crate::app::visibility::可視判定配線,
    プリミティブ描画項目台帳: &mut crate::app::primitive_draw_item_registry::プリミティブ描画項目台帳,
    進行: &ストリーミング進行,
    実破棄受け皿: &mut Vec<描画束ID>,
    大域平行移動: blitz_math::大域ワールド位置,
    一辺: チャンク一辺,
    描画除外座標: Option<チャンク座標>,
) -> Result<(), 起動エラー> {
    for 座標 in 進行.準備完了一覧() {
        if 描画除外座標 == Some(*座標) {
            描画せず転送を完了する(調停, *座標)?;
        } else {
            描画束を追加する(調停, レンダラー, 可視判定, プリミティブ描画項目台帳, *座標, 大域平行移動, 一辺)?;
        }
    }
    // 解除の予約だけを行い、台帳への報告は実破棄の引き取りまで遅らせる。予約の時点で報告すると、
    // 台帳が数えるVRAMが実確保より先に減り、空いた分へ新束を収容して実VRAMが上限を超える。
    // 可視材料は予約の時点で捨てる。レンダラーがその束を描かなくなった後も残ると、存在しない束の選択を毎フレーム作り続ける。
    for 座標 in 進行.gpu資源解除待ち一覧() {
        let 束id = 束idを作る(*座標)?;
        レンダラー.描画束を解除する(束id);
        可視判定.束を解除する(束id);
        プリミティブ描画項目台帳.束を解除する(束id);
    }
    レンダラー.実破棄済み描画束を引き取る(実破棄受け皿);
    for 束id in 実破棄受け皿.iter() {
        調停.gpu資源の解除を報告する(束idから座標を復元する(*束id))?;
    }
    Ok(())
}

/// 描画対象数へ`None`を渡すのは、複製配置がベンチ専用の機能でありチャンクの実体を歪めるためである。
/// 描画の基準原点は変換境界がこの座標から導出する。座標を渡すことで、シーンの全描画対象がこの束に属することも同じ境界で検証される。
fn 描画束を追加する(
    調停: &mut ストリーミング調停,
    レンダラー: &mut レンダラー,
    可視判定: &mut crate::app::visibility::可視判定配線,
    プリミティブ描画項目台帳: &mut crate::app::primitive_draw_item_registry::プリミティブ描画項目台帳,
    座標: チャンク座標,
    大域平行移動: blitz_math::大域ワールド位置,
    一辺: チャンク一辺,
) -> Result<(), 起動エラー> {
    let 束id = 束idを作る(座標)?;
    let Some(シーン) = 調停.gpu転送のためにシーンデータを取り出す(座標)? else {
        return Err(起動エラー::ストリーミング準備済みデータ不在(座標));
    };
    let 描画入力 = crate::app::scene_load::シーンをレンダラー入力に変換する(
        &シーン,
        crate::cli::描画対象の並べ方::そのまま読む(),
        座標,
        大域平行移動,
        Some(一辺),
    )?;
    レンダラー.描画束を追加する(束id, &描画入力.描画シーン)?;
    可視判定.束を登録する(束id, 描画入力.登録一式.可視材料一覧);
    プリミティブ描画項目台帳.束を登録する(束id, 描画入力.登録一式.プリミティブ描画項目一覧);
    調停.gpu転送の完了を報告する(座標)?;
    Ok(())
}
