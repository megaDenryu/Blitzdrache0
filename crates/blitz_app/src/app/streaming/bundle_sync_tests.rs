//! ストリーミング束が2つの永続予約IDへ入らないことを固定する。

use blitz_engine::チャンク座標;

use super::bundle_sync::{座標番号の符号ビット, 束idを作る};

#[test]
fn 予約束0へ写る座標を拒む() {
    衝突を拒む(0);
}

#[test]
fn 予約束1へ写る座標を拒む() {
    衝突を拒む(1);
}

fn 衝突を拒む(予約番号: u64) {
    let 座標 = チャンク座標::番号から復元する(予約番号 ^ 座標番号の符号ビット);
    assert!(束idを作る(座標).is_err());
}
