//! 世界差し替えの2つの工程。旧世界がレンダラーへ渡した描画束の一覧を状態を変えずに集める工程(反映準備が呼ぶ)と、
//! その一覧の束をレンダラーと描画束の台帳から解除し、調停の目録と台帳を置き換える工程(反映が呼ぶ)である。

use blitz_render::描画束ID;

use super::{bundle_sync::束idを作る, ストリーミング配線};
use crate::app::draw_bundle_ledger::描画束の台帳;
use crate::error::起動エラー;

impl ストリーミング配線 {
    /// 旧世界がレンダラーへ渡した描画束のID一覧。調停も台帳も書き換えない。
    pub(in crate::app) fn 旧世界の束一覧を集める(&self) -> Result<Vec<描画束ID>, 起動エラー> {
        let mut 座標一覧 = Vec::new();
        self.調停.gpu資源を持つ座標を集める(&mut 座標一覧);
        座標一覧.into_iter().map(束idを作る).collect()
    }

    /// 前提: 新しい目録は`チャンク目録の一辺を検査する`を通っており、束一覧は`旧世界の束一覧を集める`が同じ調停の状態から作った。
    /// 目録の差し替えを束の解除より先に置くのは、差し替えが拒まれる唯一の理由(一辺の不一致)が前提で消えており、
    /// それでも拒まれたらプログラムのバグであるため、何も解除しないうちに止めるためである。
    pub(in crate::app) fn チャンク目録と描画束を差し替える(
        &mut self, 新しい目録: blitz_engine::チャンク目録, 旧世界の束一覧: Vec<描画束ID>, レンダラー: &mut blitz_render::レンダラー, 台帳: &mut 描画束の台帳
    ) {
        if let Err(誤り) = self.調停.チャンク目録を差し替える(新しい目録) {
            panic!("一辺の検査を通した目録の差し替えを調停が拒んだ(反映準備が一辺を検査してから反映する不変条件が破れている): {誤り}");
        }
        for 束id in 旧世界の束一覧 {
            レンダラー.描画束を解除する(束id);
            台帳.束を解除する(束id);
            // 同じ座標を含む世界へ連続で差し替えると同じ束IDの破棄完了が複数届くため、完了1件につき1件を残す。
            self.差し替え前の実破棄待ち束.push(束id);
        }
    }
}
