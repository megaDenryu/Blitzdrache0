//! `cargo xtask ow3-dod`と`cargo xtask instance-stream`の2つの検収が歩く固定経路を所有する。持つのは経路の端点・1フレームの移動量・静止と整定に使うフレーム数の定数と、それらから経過フレームを導く計算である。
//! 呼び出し側はどの検収の経路かを選ぶだけで、端点も速さも静止の長さも知らずに済む。経路の値そのものはblitz_engineの`固定経路`が計算する。

use blitz_engine::固定経路;
use blitz_math::{大域メートル, 大域ワールド位置};

use crate::error::起動エラー;

/// 1フレームあたりの移動量。一辺100メートルを20フレームでまたぐため、先読み半径1の必要集合は20フレームに1回入れ替わる。
/// これより速いと読込が追いつかず、遅いと同じ回数の入れ替わりを見るのに長い実行が要る。
const 一フレーム移動量メートル: f64 = 5.0;
const 統合検収経路の始点Xメートル: f64 = 50.0;
const 統合検収経路の終点Xメートル: f64 = 250.0;
const 統合検収経路の静止フレーム数: u32 = 120;

/// インスタンス統合経路が往路と復路に使うフレーム数。始点と終点の200メートルを1フレーム5メートルで進むため往路が40フレームであり、
/// `固定経路`の三角波は80フレームで始点へ戻る。この値を過ぎたら位置を始点へ留め、必要集合が変わらない整定の局面にする。
const インスタンス統合往復フレーム数: u32 = 80;

pub(super) fn 統合経路を作る() -> Result<固定経路, 起動エラー> {
    Ok(固定経路::生成する(
        経路端点(統合検収経路の始点Xメートル),
        経路端点(統合検収経路の終点Xメートル),
        大域メートル::生成する(一フレーム移動量メートル),
    )?)
}

/// 静止して先読みする局面のぶんだけ遅らせた経過フレーム。静止のあいだは経路の始点に留まる。
pub(super) fn 統合経路の経過(フレーム番号: u32) -> u32 {
    フレーム番号.saturating_sub(統合検収経路の静止フレーム数)
}

/// 往復を終えたら経過を止め、以後は始点へ留める。三角波は往復フレーム数ちょうどで始点へ戻るため、頭打ちがそのまま整定になる。
pub(super) fn 整定込みの経過(フレーム番号: u32) -> u32 {
    統合経路の経過(フレーム番号).min(インスタンス統合往復フレーム数)
}

fn 経路端点(xメートル: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(xメートル),
        大域メートル::生成する(0.0),
        大域メートル::生成する(0.0),
    )
}
