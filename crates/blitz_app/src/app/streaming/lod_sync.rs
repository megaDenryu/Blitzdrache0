//! 常駐チャンクの詳細段を決め、レンダラーが読む束IDと段の対へ写す工程。
//! 受け取るのは調停と視点の大域位置、書き換えるのは選択の受け皿だけである。段を決めるのはエンジン側の選択器であり、ここは座標から束IDへの写像だけを足す。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「LOD」

use blitz_engine::{ストリーミング調停, チャンク座標, 地形LOD選択器, 地形LOD選択設定};
use blitz_math::{大域メートル, 大域ワールド位置};
use blitz_render::{地形詳細段, 地形詳細段選択};

use super::bundle_sync::束idを作る;
use super::一辺メートル;
use crate::error::起動エラー;

/// 詳細段を1つ粗くする距離の刻み。チャンクの一辺100メートルに対して2チャンクぶんであり、先読み半径1の常駐集合の中で段が1つ変わる。
const 基準距離メートル: f64 = 200.0;

/// 段の切替に持たせる重なりの幅。基準距離の20分の1であり、境界を跨ぐ往復で段が毎フレーム入れ替わらない。
const ヒステリシス幅メートル: f64 = 10.0;

/// 最も粗い段の番号。アセットコンパイラが焼く段数と揃える(辺分割数64から4まで5段)。
const 最粗段番号: u8 = 4;

/// 毎フレーム使い回す作業領域。3つの受け皿を同じ型が持つのは、この3つが常に同じフレームの同じ常駐集合を表すためである。
pub(super) struct 地形LOD配線 {
    選択器: 地形LOD選択器,
    常駐受け皿: Vec<チャンク座標>,
    段受け皿: Vec<(チャンク座標, 地形詳細段)>,
    束別選択: Vec<地形詳細段選択>,
    継ぎ目検査: Option<crate::cli::LOD継ぎ目検査設定>,
}

impl 地形LOD配線 {
    pub(super) fn 生成する(継ぎ目検査: Option<crate::cli::LOD継ぎ目検査設定>) -> Self {
        Self {
            選択器: 選択器を作る(),
            常駐受け皿: Vec::new(),
            段受け皿: Vec::new(),
            束別選択: Vec::new(),
            継ぎ目検査,
        }
    }

    /// 束の追加と解除を反映した後に呼ぶ。台帳が常駐としている座標と、レンダラーが持つ束が一致している時点でなければ、存在しない束の段を選ぶためである。
    pub(super) fn 選択を更新する(
        &mut self, 調停: &ストリーミング調停, 視点: 大域ワールド位置
    ) -> Result<(), 起動エラー> {
        調停.常駐座標を集める(&mut self.常駐受け皿);
        self.選択器.選択する(視点, &self.常駐受け皿, &mut self.段受け皿);
        self.束別選択.clear();
        for (座標, 段) in &self.段受け皿 {
            let 適用段 = super::lod_override::検査段を適用する(*座標, *段, self.継ぎ目検査);
            self.束別選択.push(地形詳細段選択::生成する(束idを作る(*座標)?, 適用段));
        }
        Ok(())
    }

    /// 描画入力へ借用で渡す間だけ受け皿を呼び出し元へ預ける。確保した容量を次のフレームへ持ち越すため、預けた受け皿は同じフレームのうちに`束別選択を戻す`で返す。
    /// 注意: 預けている間の`束別選択`は空である。この型へ選択を読む処理を足すときは、預ける前か返した後に読む。
    pub(super) fn 束別選択を預ける(&mut self) -> Vec<地形詳細段選択> {
        std::mem::take(&mut self.束別選択)
    }

    pub(super) fn 束別選択を戻す(&mut self, 受け皿: Vec<地形詳細段選択>) {
        self.束別選択 = 受け皿;
    }

    /// 段番号ごとの束の数。最後に選択したフレームの結果であり、段の切替が実際に起きたかどうかを実行の外から見るための観測である。
    pub(super) fn 段別の束数(&self) -> Vec<(u8, usize)> {
        let mut 集計: Vec<(u8, usize)> = Vec::new();
        for (_, 段) in &self.段受け皿 {
            match 集計.iter_mut().find(|(番号, _)| *番号 == 段.番号()) {
                Some((_, 件数)) => *件数 += 1,
                None => 集計.push((段.番号(), 1)),
            }
        }
        集計.sort_by_key(|(番号, _)| *番号);
        集計
    }
}

/// 距離の刻みとヒステリシス幅と最も粗い段はこの配線が決め、選択の規則そのものはエンジン側が持つ。
/// 定数が検証を通らない状態はこのファイルの誤りであって実行時の入力の誤りではないため、回復可能な失敗として上位へ返さず、破られた不変条件として停止する。
fn 選択器を作る() -> 地形LOD選択器 {
    let 設定 = 地形LOD選択設定::生成する(
        大域メートル::生成する(基準距離メートル),
        大域メートル::生成する(ヒステリシス幅メートル),
        地形詳細段::番号から生成する(最粗段番号),
    );
    let 設定 = match 設定 {
        Ok(値) => 値,
        Err(誤り) => panic!("地形LOD選択設定の定数が検証を満たさない: {誤り}"),
    };
    match 地形LOD選択器::生成する(設定, 大域メートル::生成する(一辺メートル)) {
        Ok(値) => 値,
        Err(誤り) => panic!("地形LOD選択器の一辺の定数が検証を満たさない: {誤り}"),
    }
}
