//! 固定経路の実行で観測したストリーミングの計器。毎フレームの処理時間、最大使用量、縮退の回数を貯め、終了時の要約を作る。
//! 触れるのは自分の集計フィールドだけであり、調停の状態は`ストリーミング進行`として読むだけで書き換えない。
//!
//! `処理時間一覧ms`には先頭のウォームアップフレームを入れない。
//! 要約の`見送りフレーム数`が大きい実行のRAM・VRAM推移は、提示が続いた実行と比較できない。提示停止中は破棄待ちが滞留しフレームループが空転するためである(参照: `_doc/計測/OW2第10段_2026-07-26.md`)。
//! 要約の`段別の束数`は、段の切替が起きたかどうかを実行の外から見るための観測である。

use std::time::Duration;

use blitz_engine::{ストリーミングメモリ量, ストリーミング転送量, ストリーミング進行, 予算判定};

use crate::app::frame_timing::{ウォームアップフレーム数, フレーム時間統計, 標本容量, 集計する};
use crate::cli::起動モード;

mod ledger_count;
mod lod_change;

pub(crate) struct ストリーミング計測 {
    処理時間一覧ms: Vec<f64>, // 調停と描画束の追加解除にかかったメインスレッド時間
    観測フレーム数: u32,
    最大使用量: ストリーミングメモリ量,
    台帳登録数: ledger_count::台帳登録数の観測,
    縮退フレーム数: u32,
    lod変更: lod_change::LOD変更計測,
}

pub(crate) struct ストリーミング要約 {
    pub(crate) 転送量: ストリーミング転送量,
    pub(crate) 上限: ストリーミングメモリ量,
    pub(crate) 最大使用量: ストリーミングメモリ量,
    pub(crate) 台帳登録数: ledger_count::台帳登録数の観測,
    pub(crate) 縮退フレーム数: u32,
    pub(crate) 観測フレーム数: u32,
    pub(crate) 見送りフレーム数: u64, // レンダラーが提示へ到達しなかったフレームの累計
    pub(crate) 処理時間統計: Option<フレーム時間統計>,
    pub(crate) 段別の束数: Vec<(u8, usize)>, // 最後のフレームで選ばれた詳細段ごとの束数
    pub(crate) lod変更フレーム数: u32,
    pub(crate) lod変更時読込開始件数: u64,
}

impl ストリーミング計測 {
    pub(super) fn 生成する(モード: 起動モード) -> Self {
        Self {
            処理時間一覧ms: Vec::with_capacity(標本容量(モード)),
            観測フレーム数: 0,
            最大使用量: ストリーミングメモリ量::生成する(0, 0),
            台帳登録数: ledger_count::台帳登録数の観測::生成する(),
            縮退フレーム数: 0,
            lod変更: lod_change::LOD変更計測::生成する(),
        }
    }

    pub(super) fn 記録する(
        &mut self,
        フレーム番号: u32,
        所要時間: Duration,
        進行: &ストリーミング進行,
        段選択: &[(blitz_engine::チャンク座標, blitz_render::地形詳細段)],
    ) {
        if フレーム番号 >= ウォームアップフレーム数 {
            self.処理時間一覧ms.push(所要時間.as_secs_f64() * 1000.0);
        }
        self.観測フレーム数 = self.観測フレーム数.saturating_add(1);
        let 使用量 = 進行.使用量();
        self.最大使用量 = ストリーミングメモリ量::生成する(
            self.最大使用量.ramバイト数.max(使用量.ramバイト数),
            self.最大使用量.vramバイト数.max(使用量.vramバイト数),
        );
        self.台帳登録数.記録する(進行.台帳登録数());
        // 優先度退避のフレームも必要集合を全部は収容できていないため縮退として数える。退避が起きたかどうかで数え方を変えると、同じ状態が判定の種類だけで別の量になる。
        if matches!(進行.判定(), 予算判定::縮退 { .. } | 予算判定::優先度退避 { .. }) {
            self.縮退フレーム数 = self.縮退フレーム数.saturating_add(1);
        }
        self.lod変更.記録する(進行, 段選択);
    }

    pub(super) fn 要約を作る(
        &self,
        転送量: ストリーミング転送量,
        上限: ストリーミングメモリ量,
        見送りフレーム数: u64,
        段別の束数: Vec<(u8, usize)>,
    ) -> ストリーミング要約 {
        ストリーミング要約 {
            転送量,
            上限,
            最大使用量: self.最大使用量,
            台帳登録数: self.台帳登録数,
            縮退フレーム数: self.縮退フレーム数,
            観測フレーム数: self.観測フレーム数,
            見送りフレーム数,
            処理時間統計: 集計する(&self.処理時間一覧ms),
            段別の束数,
            lod変更フレーム数: self.lod変更.変更フレーム数(),
            lod変更時読込開始件数: self.lod変更.変更時読込開始件数(),
        }
    }
}
