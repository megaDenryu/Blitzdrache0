//! 固定経路の実行で観測したストリーミングの計器。毎フレームの処理時間、最大使用量、縮退の回数を貯め、終了時の要約を作る。
//! 触れるのは自分の集計フィールドだけであり、調停の状態は`ストリーミング進行`として読むだけで書き換えない。

use std::time::Duration;

use blitz_engine::{ストリーミングメモリ量, ストリーミング転送量, ストリーミング進行, 予算判定};

use crate::app::frame_timing::{ウォームアップフレーム数, フレーム時間統計, 標本容量, 集計する};
use crate::cli::起動モード;

pub(crate) struct ストリーミング計測 {
    /// 調停と描画束の追加解除にかかったメインスレッド時間。先頭のウォームアップフレームは除く。
    処理時間一覧ms: Vec<f64>,
    観測フレーム数: u32,
    最大使用量: ストリーミングメモリ量,
    最大台帳登録数: usize,
    縮退フレーム数: u32,
}

pub(crate) struct ストリーミング要約 {
    pub(crate) 転送量: ストリーミング転送量,
    pub(crate) 上限: ストリーミングメモリ量,
    pub(crate) 最大使用量: ストリーミングメモリ量,
    pub(crate) 最大台帳登録数: usize,
    pub(crate) 縮退フレーム数: u32,
    pub(crate) 観測フレーム数: u32,
    pub(crate) 処理時間統計: Option<フレーム時間統計>,
}

impl ストリーミング計測 {
    pub(super) fn 生成する(モード: 起動モード) -> Self {
        Self {
            処理時間一覧ms: Vec::with_capacity(標本容量(モード)),
            観測フレーム数: 0,
            最大使用量: ストリーミングメモリ量::生成する(0, 0),
            最大台帳登録数: 0,
            縮退フレーム数: 0,
        }
    }

    pub(super) fn 記録する(&mut self, フレーム番号: u32, 所要時間: Duration, 進行: &ストリーミング進行) {
        if フレーム番号 >= ウォームアップフレーム数 {
            self.処理時間一覧ms.push(所要時間.as_secs_f64() * 1000.0);
        }
        self.観測フレーム数 = self.観測フレーム数.saturating_add(1);
        let 使用量 = 進行.使用量();
        self.最大使用量 = ストリーミングメモリ量::生成する(
            self.最大使用量.ramバイト数.max(使用量.ramバイト数),
            self.最大使用量.vramバイト数.max(使用量.vramバイト数),
        );
        self.最大台帳登録数 = self.最大台帳登録数.max(進行.台帳登録数());
        if matches!(進行.判定(), 予算判定::縮退 { .. }) {
            self.縮退フレーム数 = self.縮退フレーム数.saturating_add(1);
        }
    }

    pub(super) fn 要約を作る(
        &self, 転送量: ストリーミング転送量, 上限: ストリーミングメモリ量
    ) -> ストリーミング要約 {
        ストリーミング要約 {
            転送量,
            上限,
            最大使用量: self.最大使用量,
            最大台帳登録数: self.最大台帳登録数,
            縮退フレーム数: self.縮退フレーム数,
            観測フレーム数: self.観測フレーム数,
            処理時間統計: 集計する(&self.処理時間一覧ms),
        }
    }
}
