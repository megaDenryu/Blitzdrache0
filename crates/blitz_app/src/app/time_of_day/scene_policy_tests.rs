//! シーンの綴りと起動指定から決まる空の方針の検査。検証世界が空を持たないことと、2つの上書きが別の効き方を
//! することを固定する。照明の供給元と時間再構成方式の固定は`supply_tests`が持つ。
//!
//! 方針そのものは世界の種別だけを見るが、検査は綴りから通す。綴りの解き方と方針の引き当てが別々に壊れたときに、
//! どちらが壊れたのかをこの検査だけで言えるようにするためである。

#![allow(clippy::unwrap_used)]

mod supply_tests;

use blitz_engine::sky::世界の空方針;

use super::scene_policy;
use crate::cli::{世界の種別, 空の起動指定, 起動時シーン};

fn 種別を解く(綴り: &str) -> 世界の種別 {
    起動時シーン::綴りから解析する(綴り).unwrap().種別()
}

fn 空方針(綴り: &str, 指定: 空の起動指定) -> 世界の空方針 {
    scene_policy::世界の空方針を決める(種別を解く(綴り), 指定)
}

fn 空ありか(方針: 世界の空方針) -> bool {
    matches!(方針, 世界の空方針::空あり { .. })
}

#[test]
fn 地形世界だけが空を持ち検証世界は持たない() {
    assert!(空ありか(空方針("terrain_origin", 空の起動指定::方針に従う)));
    for 綴り in ["quad", "helmet", "shadow_scene", "fox", "vegetation_cull"] {
        assert!(!空ありか(空方針(綴り, 空の起動指定::方針に従う)), "{綴り}");
    }
}

#[test]
fn 空ありとして扱う指定は方針そのものを上書きする() {
    let 方針 = 空方針("quad", 空の起動指定::空ありとして扱う);
    assert!(空ありか(方針));
    assert!(scene_policy::空を描くか(方針, 空の起動指定::空ありとして扱う));
}

#[test]
fn 空を描かない指定は方針を残したまま空パスだけを外す() {
    let 方針 = 空方針("terrain_origin", 空の起動指定::空を描かない);
    assert!(空ありか(方針));
    assert!(!scene_policy::空を描くか(方針, 空の起動指定::空を描かない));
}

#[test]
fn 空なしの世界は指定が無ければ空を描かない() {
    let 方針 = 空方針("quad", 空の起動指定::方針に従う);
    assert!(!scene_policy::空を描くか(方針, 空の起動指定::方針に従う));
}

/// 遠方環境の契約は大気の媒体を要るため、検収世界が空を持たないと契約の構築が型付きの失敗になる。
#[test]
fn 間接照明の検収世界は空を持つ() {
    assert!(空ありか(空方針("indirect_probe", 空の起動指定::方針に従う)));
}
