//! 太陽天頂区間が何番だったかの記録。触れる状態は直近の区間識別と、区間が前のフレームから変わった回数だけであり、
//! 焼き直しの判定には1つも関わらない。
//!
//! これを置くのは、更新回数の期待を整数で立てられるようにするためである。焼き直したフレーム数は
//! 「区間が変わった回数+初回の1回」に一致しなければならず、一致しなければ鍵の正規化か間引きの刻みが壊れている。
//! 遠方環境の鍵の記録と別の型にするのは、数えている対象が違うためである。あちらは鍵の比較の答えを数え、
//! ここは焼く入力を決める区間そのものを数える。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」

use blitz_engine::sky::太陽天頂区間;

pub(crate) struct 太陽天頂区間の記録 {
    判定したフレーム数: u64,
    区間が変わった回数: u64,
    直近の区間: Option<太陽天頂区間>,
}

impl 太陽天頂区間の記録 {
    pub(crate) fn 新規() -> Self {
        Self {
            判定したフレーム数: 0,
            区間が変わった回数: 0,
            直近の区間: None,
        }
    }

    /// そのフレームの区間を記録する。1フレーム目は比べる相手が無いため変化に数えない。
    pub(crate) fn 記録する(&mut self, 区間: 太陽天頂区間) {
        self.判定したフレーム数 += 1;
        if self.直近の区間.is_some_and(|前| 前 != 区間) {
            self.区間が変わった回数 += 1;
        }
        self.直近の区間 = Some(区間);
    }

    pub(crate) fn 判定したフレーム数(&self) -> u64 {
        self.判定したフレーム数
    }

    pub(crate) fn 区間が変わった回数(&self) -> u64 {
        self.区間が変わった回数
    }

    /// 直近の区間識別。1度も判定していない実行では値が無いため、報告は「なし」と出す。
    pub(crate) fn 直近の区間識別(&self) -> Option<u16> {
        self.直近の区間.map(太陽天頂区間::区間識別)
    }
}
