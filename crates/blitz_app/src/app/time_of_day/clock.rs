//! 時刻の進行と天空状態の導出。担当するのは「ゲーム時計を進め、時刻が動いたら天空状態と空入力を導き直す」ことである。
//! 空を持つ世界だけがこの型を持つ。
//!
//! 停止中は実時刻を1度も読まない。読むと、時計を進めない起動でも実時間の取得がフレームごとに入り、
//! 既存の性能時系列の条件が指定なしで変わる(`frame`の可視個体の選別の計測と同じ理由)。
//! 停止を倍率0で表さないのは、`ゲーム時計`が停止と倍率を別に持つためである。
//! `前回の実時刻`は最初のフレームでは基準が無いため、そのフレームは時刻を進めない。

use std::time::Instant;

use blitz_engine::sky::{天空状態, 空と太陽の方針};
use blitz_engine::time::{ゲーム時計, 世界時刻, 時計進行状態, 時間倍率};
use blitz_math::大域秒;
use blitz_render::空入力;

use super::sky_input;

pub(super) struct 時間帯 {
    方針: 空と太陽の方針,
    時計: ゲーム時計,
    前回の実時刻: Option<Instant>, // 進行中のときだけ書き込む
    状態: 天空状態,
    空入力: 空入力,
}

impl 時間帯 {
    /// 倍率が`None`のときは時計を止める。既定を停止に置くのは、時刻の進行が読み戻し画像の決定性を壊すためである。
    pub(super) fn 生成する(方針: 空と太陽の方針, 初期時刻: 世界時刻, 倍率: Option<時間倍率>) -> Self {
        let mut 時計 = ゲーム時計::生成する(初期時刻, 倍率.unwrap_or_else(時間倍率::等速));
        if 倍率.is_none() {
            時計.停止する();
        }
        let 状態 = sky_input::天空状態を導く(&方針, 初期時刻);
        Self {
            空入力: sky_input::空入力を作る(&状態, &方針),
            方針,
            時計,
            前回の実時刻: None,
            状態,
        }
    }

    /// 実時間の経過を時計へ渡し、時刻が動いたぶんだけ天空状態と空入力を導き直す。停止中は何もしない。
    pub(super) fn 進める(&mut self) {
        if self.時計.進行状態() == 時計進行状態::停止中 {
            return;
        }
        let 今 = Instant::now();
        let 経過 = self.前回の実時刻.map_or(0.0, |前| 今.duration_since(前).as_secs_f64());
        self.前回の実時刻 = Some(今);
        if let Err(誤り) = self.時計.進める(大域秒::生成する(経過)) {
            panic!("ゲーム時計の進行で不変条件が破れた: {誤り}");
        }
        self.状態 = sky_input::天空状態を導く(&self.方針, self.時計.現在時刻());
        self.空入力 = sky_input::空入力を作る(&self.状態, &self.方針);
    }

    /// 任意の一日内時刻へ時計を飛ばし、天空状態と空入力を導き直す。時計の進行と独立に時刻を選ぶ検収が使う。
    pub(super) fn 時刻を据える(&mut self, 時刻: 世界時刻) {
        self.時計.時刻を設定する(時刻);
        self.状態 = sky_input::天空状態を導く(&self.方針, 時刻);
        self.空入力 = sky_input::空入力を作る(&self.状態, &self.方針);
    }

    /// この世界の空と太陽の方針。時刻から状態を導く経路と同じ方針を外から読むためにある。
    pub(super) fn 方針(&self) -> 空と太陽の方針 {
        self.方針
    }

    pub(super) fn 状態(&self) -> &天空状態 {
        &self.状態
    }

    /// 空を描くときだけ要る設定。スカイビューのベイク済み画像の観測高度をここから参照する。
    pub(super) fn 空描画方針(&self) -> blitz_engine::sky::空描画方針 {
        self.方針.空描画()
    }

    pub(super) fn 空入力(&self) -> 空入力 {
        self.空入力
    }
}
