//! 太陽円盤の可視性を起動指定へ反映する局面。担当するのは「空ありの方針から太陽円盤の放射輝度だけを
//! 0へ差し替え、他の値は一切動かさない」ことである。シェーダーへ分岐を足さないのは、`xtask sky-time`の
//! 対照撮影が円盤あり側と同一のカメラ・同一の構図で円盤の寄与だけを画素位置ごとの差分として
//! 取り出すためである(構図が変わると差分に円盤以外の画素も混じり、位置で切り分けられなくなる)。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「大気LUT腕での`sky-time`基準化と代表画素照合」

use blitz_engine::sky::{世界の空方針, 放射輝度色, 空と太陽の方針, 空描画方針};

use crate::cli::太陽円盤指定;

pub(in crate::app) fn 太陽円盤を反映する(方針: 世界の空方針, 指定: 太陽円盤指定) -> 世界の空方針 {
    if 指定 == 太陽円盤指定::描く {
        return 方針;
    }
    let 世界の空方針::空あり { 空と太陽, 既定時刻 } = 方針 else {
        return 方針;
    };
    世界の空方針::空あり {
        空と太陽: 空と太陽の方針::生成する(
            空と太陽.天球(),
            空と太陽.太陽光(),
            空と太陽.昼夜(),
            円盤を消した空描画方針を作る(空と太陽.空描画()),
            空と太陽.大気媒体(),
        ),
        既定時刻,
    }
}

/// 太陽円盤放射輝度だけを黒(0,0,0)へ差し替えた複製を作る。他の4値は元の方針から読み直すだけであり、
/// どれも既に値域検証済みであるため、ここでの失敗は`空描画方針::生成する`の検証条件が壊れていることを意味する。
fn 円盤を消した空描画方針を作る(元: 空描画方針) -> 空描画方針 {
    空描画方針::生成する(元.夜空放射輝度(), 黒(), 元.太陽円盤角半径(), 元.観測高度(), 元.太陽放射照度())
        .unwrap_or_else(|誤り| panic!("太陽円盤を消した空描画方針の再構成が値域を外れた: {誤り}"))
}

fn 黒() -> 放射輝度色 {
    放射輝度色::生成する(0.0, 0.0, 0.0).unwrap_or_else(|誤り| panic!("放射輝度0の生成が値域を外れた: {誤り}"))
}
