//! 大気のベイク済み画像の1フレーム入力を組む工程。担当するのは「大気媒体方針と天空状態と空描画方針とカメラから、
//! スカイビューキーと空中遠近キー・2つの観測条件を導き、そのフレームの生成指示と一緒に1つの入力へまとめる」ことである。
//! 受け取るのは方針と状態とカメラと更新判定、返すのはレンダラーへ渡す入力である。
//!
//! 鍵と観測条件を同じ場所で作るのは、両者が同じ値から決まり、別々の場所で作ると
//! 「鍵は変わらないのに条件だけ変わる」という食い違いが起こりうるためである。
//! カメラに依る部分は`aerial_input`が持つ。

use blitz_engine::sky::atmosphere::大気媒体方針;
use blitz_engine::sky::{スカイビューキー, 天空状態, 空描画方針, 遠方環境キー};
use blitz_math::メートル;
use blitz_render::atmosphere::{スカイビュー観測条件, 大気散乱媒体, 天空放射輝度の尺度, 天頂余弦};
use blitz_render::atmosphere_lut_input::大気のベイク済み画像の入力;
use blitz_render::distant_environment::遠方環境の入力;

use super::aerial_input;
use super::atmosphere_update::大気更新判定;
use super::clock::時間帯;
use super::distant_environment_update::遠方環境更新判定;
use super::空の再現条件;
use crate::app::frame::フレーム視点;

/// 入力を組むのに要る材料。引数の列が伸び続けるのを避けて1つに束ねる。
pub(super) struct 大気入力の材料<'a> {
    pub(super) 方針: &'a 大気媒体方針,
    pub(super) 媒体: 大気散乱媒体,
    pub(super) 状態: &'a 天空状態,
    pub(super) 空描画: 空描画方針,
    pub(super) 視点: &'a フレーム視点,
}

/// 大気の入力と、その組み立てで導いたスカイビューキー。鍵を返すのは、遠方環境キーがこのスカイビューキーを
/// 含むためであり、2度導くと同じフレームの2つの鍵が別々の値から作られうるためである。
pub(super) struct 大気入力の導出 {
    pub(super) 入力: 大気のベイク済み画像の入力,
    pub(super) スカイビュー鍵: スカイビューキー,
}

pub(super) fn 組む(材料: &大気入力の材料<'_>, 判定: &mut 大気更新判定) -> 大気入力の導出 {
    let 観測高度 = 材料.空描画.観測高度();
    // 太陽の天頂余弦は、太陽方向の天頂成分(ワールドのY)そのものである。
    let 太陽天頂余弦 = 材料.状態.太陽方向().成分()[1];
    let スカイビュー鍵 = スカイビューキー::導く(材料.方針.静的キー(), 太陽天頂余弦, 観測高度);
    let 空中遠近 = aerial_input::組む(材料.視点, 材料.状態, 観測高度, スカイビュー鍵);
    大気入力の導出 {
        入力: 大気のベイク済み画像の入力::生成する(
            材料.媒体,
            スカイビュー条件を組む(観測高度, 太陽天頂余弦),
            空中遠近.条件,
            判定.判定する(空中遠近.鍵),
        ),
        スカイビュー鍵,
    }
}

/// 遠方環境の1フレーム入力。明るさの尺度は空描画方針が正本であり、鍵はスカイビューキーへその2つを足したものである。
/// 太陽円盤放射輝度を鍵へ入れないのは、遠方環境が円盤を除いた連続な天空放射輝度だけを保持するためである。
pub(super) fn 遠方環境を組む(
    空描画: 空描画方針, スカイビュー鍵: スカイビューキー, 判定: &mut 遠方環境更新判定
) -> 遠方環境の入力 {
    let 鍵 = 遠方環境キー::導く(スカイビュー鍵, 空描画.太陽放射照度(), 空描画.夜空放射輝度());
    遠方環境の入力::生成する(尺度を組む(空描画), 判定.判定する(鍵))
}

/// 空描画方針の2つの値を天空放射輝度の尺度へ写す。方針の生成が有限性と符号を検証済みのため、ここでの失敗は
/// 写しが不変条件を運べていないことを意味し、破れた不変条件を示して停止する。
fn 尺度を組む(空描画: 空描画方針) -> 天空放射輝度の尺度 {
    天空放射輝度の尺度::生成する(空描画.太陽放射照度(), 空描画.夜空放射輝度().成分())
        .unwrap_or_else(|誤り| panic!("空描画方針から天空放射輝度の尺度を作れなかった: {誤り}"))
}

/// 空代表画素の照合に要る材料をまとめる。大気入力と同じ大気・時間帯から作るため、組む場所をここへ寄せる。
pub(super) fn 再現条件を組む(媒体: 大気散乱媒体, 時間帯: &時間帯) -> 空の再現条件 {
    空の再現条件 {
        大気: 媒体,
        太陽方向: 時間帯.状態().太陽方向().成分(),
        空描画: 時間帯.空描画方針(),
    }
}

/// 太陽の天頂余弦は単位ベクトルの成分であることを型が保証するため値域を外れない。観測高度は方針が0以上を検証済みである。
/// したがってここでの失敗は写しが不変条件を運べていないことを意味し、起動時の設定不備ではないため型付きエラーへは
/// 載せず、破れた不変条件を示して停止する(空入力の組み立てと同じ扱い)。
fn スカイビュー条件を組む(観測高度: メートル, 太陽天頂余弦: f32) -> スカイビュー観測条件 {
    let 余弦 =
        天頂余弦::生成する(太陽天頂余弦.clamp(-1.0, 1.0)).unwrap_or_else(|誤り| panic!("太陽方向の天頂成分から天頂余弦を作れなかった: {誤り}"));
    スカイビュー観測条件::生成する(観測高度, 余弦)
        .unwrap_or_else(|誤り| panic!("観測高度と太陽天頂余弦からスカイビュー観測条件を作れなかった: {誤り}"))
}
