//! 大気LUTの1フレーム入力を組む工程。担当するのは「大気媒体方針と天空状態と空描画方針から、
//! スカイビューキーと観測条件を導き、そのフレームの生成指示と一緒に1つの入力へまとめる」ことである。
//! 受け取るのは方針と状態と更新判定、返すのはレンダラーへ渡す入力である。
//!
//! 鍵と観測条件を同じ場所で作るのは、両者が同じ2つの値(太陽天頂余弦と観測高度)から決まり、
//! 別々の場所で作ると「鍵は変わらないのに条件だけ変わる」という食い違いが起こりうるためである。

use blitz_engine::sky::atmosphere::大気媒体方針;
use blitz_engine::sky::{スカイビューキー, 天空状態, 空描画方針};
use blitz_math::メートル;
use blitz_render::atmosphere::{スカイビュー観測条件, 大気散乱媒体, 天頂余弦};
use blitz_render::atmosphere_lut_input::大気LUT入力;

use super::atmosphere_update::大気更新判定;

pub(super) fn 組む(
    方針: &大気媒体方針, 媒体: 大気散乱媒体, 状態: &天空状態, 空描画: 空描画方針, 判定: &mut 大気更新判定
) -> 大気LUT入力 {
    let 観測高度 = 空描画.観測高度();
    // 太陽の天頂余弦は、太陽方向の天頂成分(ワールドのY)そのものである。
    let 太陽天頂余弦 = 状態.太陽方向().成分()[1];
    let 鍵 = スカイビューキー::導く(方針.静的キー(), 太陽天頂余弦, 観測高度);
    大気LUT入力::生成する(媒体, 観測条件を組む(観測高度, 太陽天頂余弦), 判定.判定する(鍵))
}

/// 太陽の天頂余弦は単位ベクトルの成分であることを型が保証するため値域を外れない。観測高度は方針が0以上を検証済みである。
/// したがってここでの失敗は写しが不変条件を運べていないことを意味し、起動時の設定不備ではないため型付きエラーへは
/// 載せず、破れた不変条件を示して停止する(空入力の組み立てと同じ扱い)。
fn 観測条件を組む(観測高度: メートル, 太陽天頂余弦: f32) -> スカイビュー観測条件 {
    let 余弦 =
        天頂余弦::生成する(太陽天頂余弦.clamp(-1.0, 1.0)).unwrap_or_else(|誤り| panic!("太陽方向の天頂成分から天頂余弦を作れなかった: {誤り}"));
    スカイビュー観測条件::生成する(観測高度, 余弦)
        .unwrap_or_else(|誤り| panic!("観測高度と太陽天頂余弦からスカイビュー観測条件を作れなかった: {誤り}"))
}
