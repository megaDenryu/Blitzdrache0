//! 遠方環境の更新の間引き。担当するのは「そのフレームの太陽の天頂余弦が属する太陽天頂区間を決め、そのフレームの
//! 生成パスがGPUへ届いたときにだけ記録へ数える」ことである。触れる状態は刻みと保留中の区間と記録の3つだけであり、
//! 鍵にも焼き直しの判定にも触れない。
//!
//! 刻みと記録を1つの型にするのは、記録が数える区間がその刻みで決まるためである。別々に持つと、
//! 刻みを変えた実行と記録の区間識別が別の刻みを指しうる。
//!
//! 決定と確定を2段に分けるのは、区間を決めたフレームが提示へ到達しない経路があるためである。レンダラー未生成・
//! 最小化中・スワップチェーン再構築中のフレームは生成パスがGPUへ1本も届かない。決めた時点で数えると、
//! 間接照明生成パス数が数えるフレームの集合とここが数えるフレームの集合が食い違い、検収の厳密一致
//! (焼き直したフレーム数=区間が変わった回数+初回の1回)が実行条件次第で成り立たなくなる
//! (参照: `crates/blitz_app/src/app/time_of_day/distant_environment_update.rs`の同じ2段)。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」

use blitz_engine::sky::{太陽天頂区間, 間引きの刻みの設定};

use super::sun_zenith_interval_record::太陽天頂区間の記録;

pub(crate) struct 遠方環境の間引き {
    /// 起動時に決まり、以降変わらない刻み。
    刻み: 間引きの刻みの設定,
    /// そのフレームで決めた区間。生成パスがGPUへ届いたことをまだ確かめていない。
    保留中の区間: Option<太陽天頂区間>,
    記録: 太陽天頂区間の記録,
}

impl 遠方環境の間引き {
    pub(crate) fn 新規() -> Self {
        Self {
            刻み: 間引きの刻みの設定::初期値(),
            保留中の区間: None,
            記録: 太陽天頂区間の記録::新規(),
        }
    }

    /// 天頂余弦が属する区間を決めて保留に置く。天頂余弦は単位ベクトルの天頂成分であり非有限になりえないため、
    /// ここでの失敗は写しが不変条件を運べていないことを意味し、破れた不変条件を示して停止する。
    pub(crate) fn 区間を決める(&mut self, 太陽天頂余弦: f32) -> 太陽天頂区間 {
        let 区間 = 太陽天頂区間::属する区間(太陽天頂余弦, self.刻み)
            .unwrap_or_else(|誤り| panic!("太陽方向の天頂成分から太陽天頂区間を作れなかった: {誤り}"));
        self.保留中の区間 = Some(区間);
        区間
    }

    /// 直前に区間を決めたフレームが提示へ到達したときに呼ぶ。保留中の区間だけを記録へ数える。
    /// 到達しなかったフレームで呼ばないことが、届かなかった更新を数えない唯一の担保である。
    pub(crate) fn 確定する(&mut self) {
        if let Some(区間) = self.保留中の区間.take() {
            self.記録.記録する(区間);
        }
    }

    pub(crate) fn 記録(&self) -> &太陽天頂区間の記録 {
        &self.記録
    }
}
