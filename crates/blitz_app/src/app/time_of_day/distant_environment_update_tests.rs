//! 遠方環境の更新判定の検査。鍵の完全性を4つの向きから見る。初回は必ず焼くこと・同じ鍵なら焼かないこと・
//! 依存値を1つ変えると焼き直すこと・太陽の方位だけを変えても焼かないことである。
//!
//! 最後の2つが設計の主張そのものである。太陽相対座標で焼くため方位は鍵に入らず、明るさの尺度は画素へ掛かるため入る。
//!
//! 検査が`提示したフレーム`を通すのは、判定と確定が2段に分かれているためである。提示へ到達しなかった
//! フレームで鍵が確定しないことは`bake_commit_tests`が2つの判定の両方について見る。

#![allow(clippy::unwrap_used)]

use blitz_engine::sky::atmosphere::大気媒体方針;
use blitz_engine::sky::{スカイビューキー, 放射輝度色, 遠方環境キー};
use blitz_math::メートル;
use blitz_render::distant_environment::input::遠方環境の生成指示;

use super::distant_environment_update::遠方環境更新判定;

const 既定の太陽天頂余弦: f32 = 0.5;
const 観測高度: f32 = 1.5;
const 既定の太陽放射照度: f32 = 20.0;

fn 夜空() -> 放射輝度色 {
    放射輝度色::生成する(0.002, 0.002, 0.005).unwrap()
}

fn 鍵(太陽天頂余弦: f32, 太陽放射照度: f32, 夜空放射輝度: 放射輝度色) -> 遠方環境キー {
    let スカイビュー = スカイビューキー::導く(大気媒体方針::地球標準().静的キー(), 太陽天頂余弦, メートル::生成する(観測高度));
    遠方環境キー::導く(スカイビュー, 太陽放射照度, 夜空放射輝度)
}

fn 既定の鍵() -> 遠方環境キー {
    鍵(既定の太陽天頂余弦, 既定の太陽放射照度, 夜空())
}

/// 判定した結果が提示へ到達したフレーム。判定して確定するところまでを1回として扱う。
fn 提示したフレーム(判定: &mut 遠方環境更新判定, 鍵: 遠方環境キー) -> 遠方環境の生成指示 {
    let 指示 = 判定.判定する(鍵);
    判定.確定する();
    指示
}

/// 初回のフレームを焼いて確定する。どの検査も「まだ1度も焼いていない」状態から始めるためである。
fn 初回を焼く(判定: &mut 遠方環境更新判定) {
    assert_eq!(提示したフレーム(判定, 既定の鍵()), 遠方環境の生成指示::焼き直す, "初回に焼かなかった");
}

/// まだ1度も焼いていないフレームは必ず焼き、同じ鍵が続くフレームは焼かない。
#[test]
fn 初回は焼き同じ鍵では焼かない() {
    let mut 判定 = 遠方環境更新判定::新規();
    初回を焼く(&mut 判定);
    assert_eq!(
        提示したフレーム(&mut 判定, 既定の鍵()),
        遠方環境の生成指示::前の結果を使う,
        "同じ鍵で焼き直した"
    );
    assert_eq!(
        提示したフレーム(&mut 判定, 既定の鍵()),
        遠方環境の生成指示::前の結果を使う,
        "同じ鍵で焼き直した"
    );
}

/// 鍵が持つ依存値を1つずつ変えると、どれを変えても焼き直す。
#[test]
fn 依存値を1つ変えると焼き直す() {
    let 変えた鍵一覧 = [
        ("太陽の高度", 鍵(0.6, 既定の太陽放射照度, 夜空())),
        ("太陽放射照度", 鍵(既定の太陽天頂余弦, 21.0, 夜空())),
        (
            "夜空放射輝度",
            鍵(既定の太陽天頂余弦, 既定の太陽放射照度, 放射輝度色::生成する(0.002, 0.002, 0.006).unwrap()),
        ),
    ];
    for (名前, 変えた鍵) in 変えた鍵一覧 {
        let mut 判定 = 遠方環境更新判定::新規();
        初回を焼く(&mut 判定);
        assert_eq!(
            提示したフレーム(&mut 判定, 変えた鍵),
            遠方環境の生成指示::焼き直す,
            "{名前}を変えたのに焼き直さなかった"
        );
    }
}

/// 太陽の方位は鍵の構成要素に1つも現れないため、方位だけが動いたフレームの鍵は前回と等しい。
/// スカイビューキーが方位を持たず、遠方環境キーが足すのが明るさの2値だけであることの帰結である。
#[test]
fn 太陽の方位だけの変化では焼かない() {
    let mut 判定 = 遠方環境更新判定::新規();
    初回を焼く(&mut 判定);
    // 方位が変わっても天頂余弦・観測高度・大気・明るさが同じであれば、導かれる鍵は同じ値になる。
    let 方位だけ動いた鍵 = 鍵(既定の太陽天頂余弦, 既定の太陽放射照度, 夜空());
    assert_eq!(
        提示したフレーム(&mut 判定, 方位だけ動いた鍵),
        遠方環境の生成指示::前の結果を使う,
        "方位だけの変化で焼き直した"
    );
}
