//! 遠方環境の更新を間引いたときに区間の境界で生じる段差を撮る走査。担うのは「起動指定を、一日の跨ぎの一覧の
//! 該当ぶんの撮影の列へ開き、フレーム番号から今どの撮影のどのフレームかを答える」ことである。
//! 書き出し先の組み立ては読み戻しの側が持ち、ここはファイル名に足す語だけを答える。
//!
//! 対の2枚を時刻を動かさずに撮るのがこの走査の要点である。カメラ・連続の太陽方向・直接光・空背景は境界を
//! 跨いだ時刻に固定し、遠方環境を焼く区間だけを下側と上側へ差し替える。実時刻を境界の前後へ動かすと、
//! 直接光と空背景の連続変化が差へ混ざり、間接照明の段差だけを測れなくなる。
//!
//! 跨ぎの一覧を起動指定で受け取らずここで列挙し直すのは、検収側が刻みと球面天文学を写した表を持たないためである。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」

mod range;
mod shot;

use blitz_engine::sky::{一日の区間の跨ぎを列挙する, 太陽天頂区間の跨ぎ, 空と太陽の方針, 間引きの刻みの設定};
use range::一撮影のフレーム数;
pub(crate) use range::段差走査の指定;
use shot::撮影の側;
pub(in crate::app) use shot::撮影指定;

use crate::cli::起動引数エラー;

pub(in crate::app) struct 段差走査 {
    撮影一覧: Vec<撮影指定>,
}

impl 段差走査 {
    /// 起動指定を撮影の列へ開く。指定が一日の跨ぎの外にあれば、番号と一日の件数を示して落とす。
    pub(in crate::app) fn 組む(
        指定: 段差走査の指定, 方針: &空と太陽の方針, 刻み: 間引きの刻みの設定
    ) -> Result<Self, 起動引数エラー> {
        let 跨ぎ一覧 = 一日の区間の跨ぎを列挙する(方針, 刻み)
            .map_err(|誤り| 起動引数エラー::段差走査範囲不正(format!("跨ぎを列挙できなかった: {誤り}")))?;
        let 開始 = usize::from(指定.最初の跨ぎ番号());
        let 終端 = 開始 + usize::from(指定.跨ぎの件数());
        let 該当 = 跨ぎ一覧.get(開始..終端).ok_or_else(|| {
            起動引数エラー::段差走査範囲不正(format!("跨ぎ番号{開始}から{終端}は一日の跨ぎ{}件の外にある", 跨ぎ一覧.len()))
        })?;
        let mut 撮影一覧 = Vec::new();
        for 跨ぎ in 該当 {
            積む(&mut 撮影一覧, *跨ぎ, 指定, 刻み)?;
        }
        println!(
            "段差の走査 最初の跨ぎ番号={} 跨ぎの件数={} 撮影数={}",
            指定.最初の跨ぎ番号(),
            指定.跨ぎの件数(),
            撮影一覧.len()
        );
        Ok(Self { 撮影一覧 })
    }

    /// そのフレームで撮っている撮影。撮り終えた後のフレームでは無い。
    pub(in crate::app) fn このフレームの撮影(&self, 現在フレーム: u32) -> Option<撮影指定> {
        let 番号 = usize::try_from(現在フレーム / 一撮影のフレーム数).unwrap_or(usize::MAX);
        self.撮影一覧.get(番号).copied()
    }

    /// そのフレームが撮影の最後のフレームか。ここでだけ読み戻して書き出す。
    pub(in crate::app) fn このフレームで読み戻すか(&self, 現在フレーム: u32) -> bool {
        現在フレーム % 一撮影のフレーム数 == 一撮影のフレーム数 - 1 && self.このフレームの撮影(現在フレーム).is_some()
    }
}

/// 1つの跨ぎぶんの撮影を積む。下側の区間を先に積むのは、報告と生値の並びを境界の下から上への向きに揃えるためである。
/// 対照は上側を挟んで下側をもう1枚積み、1枚目と3枚目の一致で状態の持ち越しと一回限りの揺れを反証できるようにする。
fn 積む(
    撮影一覧: &mut Vec<撮影指定>,
    跨ぎ: 太陽天頂区間の跨ぎ,
    指定: 段差走査の指定,
    刻み: 間引きの刻みの設定,
) -> Result<(), 起動引数エラー> {
    let 上側 = 跨ぎ.上側の区間();
    let 下側の識別 = 上側
        .区間識別()
        .checked_sub(1)
        .ok_or_else(|| 起動引数エラー::段差走査範囲不正("いちばん下の区間に下側の区間が無い".to_string()))?;
    let 下側 = blitz_engine::sky::太陽天頂区間::識別から作る(下側の識別, 刻み)
        .map_err(|誤り| 起動引数エラー::段差走査範囲不正(format!("下側の区間を作れなかった: {誤り}")))?;
    let mut 側一覧 = vec![(下側, 撮影の側::下側の区間), (上側, 撮影の側::上側の区間)];
    if matches!(指定, 段差走査の指定::対照 { .. }) {
        側一覧.push((下側, 撮影の側::下側の区間の撮り直し));
    }
    for (区間, 側) in 側一覧 {
        撮影一覧.push(撮影指定 {
            一日内秒: 跨ぎ.一日内秒(),
            区間,
            跨ぎ: (上側.区間識別(), 跨ぎ.方向()),
            側,
        });
    }
    Ok(())
}
