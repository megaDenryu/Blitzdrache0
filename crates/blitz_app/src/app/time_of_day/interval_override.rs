//! 検収のための太陽天頂区間の上書き。担うのは「そのフレームの遠方環境をどの区間の代表値で焼くかを、
//! 連続な天頂余弦から決めるか、指定された区間識別から決めるか」の別だけである。
//!
//! 起動指定でなく型の枝で持つのは、上書きが指定されない実行で本番の経路が1つも変わらないことを網羅的な
//! `match`で示せるためである。真偽値と区間識別を並べて持つと、真偽値が偽のときの識別が意味を持たない値になる。
//!
//! 上書きが要るのは、境界の段差を測るには時刻を動かさずに区間だけを前後へ差し替えなければならないためである。
//! 実時刻を境界の前後へ動かすと、直接光と空背景の連続変化が差へ混ざり、間接照明の段差だけを測れなくなる。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」

use blitz_engine::sky::{天空状態エラー, 太陽天頂区間, 間引きの刻みの設定};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 太陽天頂区間の上書き {
    上書きしない,                 // 本番。そのフレームの連続な太陽天頂余弦が属する区間を使う
    指定の区間 { 区間識別: u16 }, // 検収。天頂余弦を読まず、指定された区間識別の区間を使う
}

impl 太陽天頂区間の上書き {
    pub(crate) fn 区間を決める(
        self, 太陽天頂余弦: f32, 刻み: 間引きの刻みの設定
    ) -> Result<太陽天頂区間, 天空状態エラー> {
        match self {
            Self::上書きしない => 太陽天頂区間::属する区間(太陽天頂余弦, 刻み),
            Self::指定の区間 { 区間識別 } => 太陽天頂区間::識別から作る(区間識別, 刻み),
        }
    }
}
