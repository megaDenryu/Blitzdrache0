//! 大気のベイク済み画像のどれを焼き直すかを決める工程。担当するのは「空中遠近キーを前フレームの値と比べ、鍵のどの層が
//! 変わったかで4つの指示のどれかを返す」ことである。触れる状態は前回の鍵1つだけである。
//!
//! 鍵は大気・スカイビュー・空中遠近の3層の入れ子であり、外側が変われば内側も必ず変わる。比較を外側から順に行い、
//! 最初に食い違った層に応じた指示を返す。
//!
//! 可変なdirty通知でなく鍵の値の比較で決めるのは、通知の付け忘れが「方針を変えたのに古いベイク済み画像を参照し続ける」という
//! 絵にしか現れない欠陥になるためである。鍵は方針の全パラメータと太陽の向きと観測高度を並べた完全比較キーであり、
//! 要約の衝突では等しくならない。履歴・乱数・フレーム番号・時間積算を判定へ入れない
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「更新の決定性」)。

use blitz_engine::sky::空中遠近キー;
use blitz_render::atmosphere_lut_input::大気のベイク済み画像の生成指示;

pub(in crate::app) struct 大気更新判定 {
    /// 直近に焼いたときの鍵。まだ1度も焼いていないフレームでは`None`であり、最初のフレームが必ず4枚を焼く。
    前回焼いた鍵: Option<空中遠近キー>,
}

impl 大気更新判定 {
    pub(in crate::app) fn 新規() -> Self {
        Self { 前回焼いた鍵: None }
    }

    /// そのフレームの鍵を受け取り、何を焼き直すかを返す。焼き直すと答えたときは鍵を記録する。
    pub(in crate::app) fn 判定する(&mut self, 鍵: 空中遠近キー) -> 大気のベイク済み画像の生成指示 {
        let 指示 = self.指示を決める(鍵);
        if 指示 != 大気のベイク済み画像の生成指示::前の結果を使う {
            self.前回焼いた鍵 = Some(鍵);
        }
        指示
    }

    fn 指示を決める(&self, 鍵: 空中遠近キー) -> 大気のベイク済み画像の生成指示 {
        let Some(前回) = self.前回焼いた鍵 else {
            return 大気のベイク済み画像の生成指示::全部焼き直す;
        };
        if 前回.スカイビューの鍵().大気の鍵() != 鍵.スカイビューの鍵().大気の鍵() {
            return 大気のベイク済み画像の生成指示::全部焼き直す;
        }
        if 前回.スカイビューの鍵() != 鍵.スカイビューの鍵() {
            return 大気のベイク済み画像の生成指示::スカイビューと空中遠近を焼き直す;
        }
        if 前回 == 鍵 {
            return 大気のベイク済み画像の生成指示::前の結果を使う;
        }
        大気のベイク済み画像の生成指示::空中遠近だけ焼き直す
    }
}
