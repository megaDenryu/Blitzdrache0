//! 大気LUTのどれを焼き直すかを決める工程。担当するのは「スカイビューキーを前フレームの値と比べ、
//! 大気の部分が変わったなら3枚すべて、鍵の残りだけが変わったならスカイビューだけを焼く指示を返す」ことである。
//! 触れる状態は前回の鍵1つだけである。
//!
//! 可変なdirty通知でなく鍵の値の比較で決めるのは、通知の付け忘れが「方針を変えたのに古いLUTを引き続ける」という
//! 絵にしか現れない欠陥になるためである。鍵は方針の全パラメータと太陽の向きと観測高度を並べた完全比較キーであり、
//! 要約の衝突では等しくならない。履歴・乱数・フレーム番号・時間積算を判定へ入れない
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「更新の決定性」)。

use blitz_engine::sky::スカイビューキー;
use blitz_render::atmosphere_lut_input::大気LUT生成指示;

pub(in crate::app) struct 大気更新判定 {
    /// 直近に焼いたときの鍵。まだ1度も焼いていないフレームでは`None`であり、最初のフレームが必ず3枚を焼く。
    前回焼いた鍵: Option<スカイビューキー>,
}

impl 大気更新判定 {
    pub(in crate::app) fn 新規() -> Self {
        Self { 前回焼いた鍵: None }
    }

    /// そのフレームの鍵を受け取り、何を焼き直すかを返す。焼き直すと答えたときは鍵を記録する。
    pub(in crate::app) fn 判定する(&mut self, 鍵: スカイビューキー) -> 大気LUT生成指示 {
        let 指示 = self.指示を決める(鍵);
        if 指示 != 大気LUT生成指示::前の結果を使う {
            self.前回焼いた鍵 = Some(鍵);
        }
        指示
    }

    fn 指示を決める(&self, 鍵: スカイビューキー) -> 大気LUT生成指示 {
        let Some(前回) = self.前回焼いた鍵 else {
            return 大気LUT生成指示::全部焼き直す;
        };
        if 前回.大気の鍵() != 鍵.大気の鍵() {
            return 大気LUT生成指示::全部焼き直す;
        }
        if 前回 == 鍵 {
            return 大気LUT生成指示::前の結果を使う;
        }
        大気LUT生成指示::スカイビューだけ焼き直す
    }
}
