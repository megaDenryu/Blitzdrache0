//! 大気LUTを焼き直すかどうかを決める工程。担当するのは「大気静的キーを前フレームの値と比べ、
//! 変わったフレームだけ焼き直す指示を返す」ことである。触れる状態は前回の鍵1つだけである。
//!
//! 可変なdirty通知でなく鍵の値の比較で決めるのは、通知の付け忘れが「方針を変えたのに古いLUTを引き続ける」という
//! 絵にしか現れない欠陥になるためである。鍵は方針の全パラメータを並べた完全比較キーであり、要約の衝突では等しくならない。
//! 履歴・乱数・フレーム番号・時間積算を判定へ入れない(参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「更新の決定性」)。

use blitz_engine::sky::atmosphere::大気静的キー;
use blitz_render::atmosphere_lut_input::大気LUT生成指示;

pub(in crate::app) struct 大気更新判定 {
    /// 直近に焼いたときの鍵。まだ1度も焼いていないフレームでは`None`であり、最初のフレームが必ず焼く。
    前回焼いた鍵: Option<大気静的キー>,
}

impl 大気更新判定 {
    pub(in crate::app) fn 新規() -> Self {
        Self { 前回焼いた鍵: None }
    }

    /// そのフレームの鍵を受け取り、焼き直すかどうかを返す。焼き直すと答えたときは鍵を記録する。
    pub(in crate::app) fn 判定する(&mut self, 鍵: 大気静的キー) -> 大気LUT生成指示 {
        if self.前回焼いた鍵 == Some(鍵) {
            return 大気LUT生成指示::前の結果を使う;
        }
        self.前回焼いた鍵 = Some(鍵);
        大気LUT生成指示::焼き直す
    }
}
