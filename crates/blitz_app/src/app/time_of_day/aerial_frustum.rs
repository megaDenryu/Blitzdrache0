//! カメラ相対のビュー射影の逆から、空中遠近ボリュームが要る視錐台の向きと最遠距離を取り出す工程。
//! 受け取るのはずらし無しのビュー射影の逆変換、返すのは基準の向きと横縦の差分と最遠距離である。
//!
//! 注意: 深度の端点は逆向き深度の規約に従う。近平面が深度1、遠平面が深度0である
//! (参照: `crates/blitz_math/src/frame/transform_construct.rs`の`逆向き深度の透視投影`)。
//! 正の向きの深度の規約で端点を組むと、最遠距離が遠クリップでなく近クリップの長さになり、
//! 向きもカメラの真後ろを指す。空中遠近ボリュームは近クリップぶんの空気しか積まなくなり、
//! 合成が8ビットの絵の上で恒等に見える。
//!
//! 視線の向きを「遠平面の点から近平面の点を引いた差」で作るのは、この差がカメラの位置を含まないためである。
//! 位置を含めると大域原点の移動で値が変わり、カメラ相対契約が破れる。差は画面の単位位置についてアフィンであるため、
//! 基準と横縦の差分の3つで厳密に表せる(遠平面も近平面もクリップ座標のwが一定である)。
//!
//! 最遠距離を画面中央の遠平面の点の長さで測るのは、カメラ相対フレームの原点がカメラ自身の大域位置に置かれており、
//! カメラの相対位置が厳密に0だからである(`crate::app::frame::draw_input`の`視点を求める`が決めている)。

use blitz_math::{クリップ, メートル, ワールド, 位置, 変換};

const 遠面の深度: f32 = 0.0;
const 近面の深度: f32 = 1.0;

/// 画面の単位位置から視線の向きを与えるアフィン写像の3成分と、視錐台の中央が届く距離。
/// 空中遠近の観測条件と焼き直しの鍵が、どちらもこの4つの値から決まる。
pub(super) struct 視錐台の向きと最遠距離 {
    pub(super) 基準: [f32; 3],
    pub(super) 横の差分: [f32; 3],
    pub(super) 縦の差分: [f32; 3],
    pub(super) 最遠距離: メートル,
}

impl 視錐台の向きと最遠距離 {
    pub(super) fn カメラ相対ビュー射影の逆から導く(逆変換: &変換<クリップ, ワールド>) -> Self {
        let 遠端 = |横: f32, 縦: f32| 画面の点(逆変換, 横, 縦, 遠面の深度);
        let 近端 = |横: f32, 縦: f32| 画面の点(逆変換, 横, 縦, 近面の深度);
        let 向き = |横: f32, 縦: f32| 三成分の差を求める(遠端(横, 縦), 近端(横, 縦));
        let 基準 = 向き(0.0, 0.0);
        Self {
            横の差分: 三成分の差を求める(向き(1.0, 0.0), 基準),
            縦の差分: 三成分の差を求める(向き(0.0, 1.0), 基準),
            最遠距離: メートル::生成する(三成分の長さを求める(遠端(0.5, 0.5))),
            基準,
        }
    }
}

/// 画面の単位位置と深度から、カメラ相対フレームでの点を求める。Vulkanの正規化デバイス座標は縦が下向きであり、
/// 画面の単位位置の縦0が上端に対応する。透視除算は`適用する`が行う。
fn 画面の点(逆変換: &変換<クリップ, ワールド>, 横: f32, 縦: f32, 深度: f32) -> [f32; 3] {
    let クリップ点 = 位置::<クリップ>::生成する(
        メートル::生成する(横 * 2.0 - 1.0),
        メートル::生成する(縦 * 2.0 - 1.0),
        メートル::生成する(深度),
    );
    let 点 = 逆変換.適用する(クリップ点);
    [点.x().値(), 点.y().値(), 点.z().値()]
}

fn 三成分の差を求める(左: [f32; 3], 右: [f32; 3]) -> [f32; 3] {
    [左[0] - 右[0], 左[1] - 右[1], 左[2] - 右[2]]
}

fn 三成分の長さを求める(値: [f32; 3]) -> f32 {
    (値[0] * 値[0] + 値[1] * 値[1] + 値[2] * 値[2]).max(0.0).sqrt()
}
