//! 世界方針から積むパスの本数までを、本番の導出関数の連なりで通す検査。担当するのは「シーン名→世界の
//! 間接照明方針→照明問い合わせ契約→資源の要否→生成パス数の内訳」を1本に繋いで反証することである。
//!
//! 段ごとに分けた検査だけでは足りないことが分かっているためこれを置く。契約の枝と本数の内訳はそれぞれ単体で
//! 反証されていたが、「空を描かない起動では大気のベイク済み画像が作られず遠方環境が焼けない」という段と段の
//! つなぎ目の不整合はどの単体検査も落とさなかった。
//!
//! 終端の本数は本番のレンダーグラフが返すのと同じ`焼き上げの計画::本数`が答える。検査のためだけに内訳を合成すると、本番のグラフが0本や誤った本数を積んでもこの検査は通ってしまう。
//! GPUを1つも開かないのは、ここで見たいのが資源の中身でなく条件の連なりだからである。

#![allow(clippy::unwrap_used)]

use blitz_engine::sky::世界の間接照明方針;
use blitz_render::distant_environment::input::遠方環境の生成指示;
use blitz_render::distant_environment::間接照明生成パス数;
use blitz_render::indirect_lighting::{焼き上げの計画, 焼き始めの記録, 照明問い合わせ契約, 間接照明契約エラー};

use super::scene_policy;

/// 鏡面畳込みの既定の粗さ段数。最詳細段は複製で作るため計算で焼くのは1つ少ない。
const 鏡面の粗さ段数: u32 = 6;
const 計算で焼く鏡面の段数: u32 = 鏡面の粗さ段数 - 1;

/// 連なりを1回通した結果。
struct 連なりの結果 {
    契約: 照明問い合わせ契約,
    大気の資源: bool,
    遠方環境の資源: bool,
    初回フレームの本数: 間接照明生成パス数,
}

/// 本番と同じ導出関数だけを使って、世界の宣言から1フレームの本数までを導く。
///
/// 本数は`焼き始めの記録`が決めた計画に答えさせる。この2つはレンダーグラフの積み上げが使うものと同じであり、
/// 検査のために内訳を組み立て直す経路をここへ作らない。
fn 通す(
    方針: 世界の間接照明方針, 大気媒体あり: bool, 空を描く: bool
) -> Result<連なりの結果, 間接照明契約エラー> {
    let 契約 = 方針.照明問い合わせ契約へ写す(大気媒体あり)?;
    let 遠方環境の資源 = 契約.遠方環境の資源を作るか();
    Ok(連なりの結果 {
        契約,
        大気の資源: 契約.大気のベイク済み画像を作るか(空を描く),
        遠方環境の資源,
        // 資源を作らない契約では描画入力そのものが作られないため、段の展開は1本も積まない。
        初回フレームの本数: if 遠方環境の資源 {
            初回フレームの計画().本数()
        } else {
            間接照明生成パス数::焼かない()
        },
    })
}

/// 起動直後の1フレーム目の計画。まだ1度も焼いていないため、上位層の指示が「前の結果を使う」でも焼き直しへ格上げされる。
fn 初回フレームの計画() -> 焼き上げの計画 {
    焼き始めの記録::新規().計画を決める(遠方環境の生成指示::前の結果を使う, 鏡面の粗さ段数)
}

/// 地形でも間接照明の検収でもない世界は定数近似であり、空を描く描かないに依らず遠方環境のパスを1本も積まない。
#[test]
fn 地形以外の世界名はどれも定数近似で本数が0になる() {
    for シーン名 in ["quad", "helmet", "shadow_scene", "fox", "vegetation_4", "prop_village"] {
        let 方針 = scene_policy::世界の間接照明方針を決める(シーン名);
        assert_eq!(方針, 世界の間接照明方針::定数近似, "{シーン名}が定数近似でない");
        for 空を描く in [true, false] {
            let 結果 = 通す(方針, true, 空を描く).unwrap();
            assert_eq!(結果.契約, 照明問い合わせ契約::定数近似);
            assert!(!結果.遠方環境の資源, "{シーン名}が遠方環境の資源を作る");
            assert_eq!(結果.初回フレームの本数, 間接照明生成パス数::焼かない(), "{シーン名}がパスを積む");
            // 定数近似の大気の資源は空を描くかどうかだけで決まる。既存の判定値が動かないことの土台である。
            assert_eq!(結果.大気の資源, 空を描く, "{シーン名}の大気の資源が空の有無で決まらない");
        }
    }
}

/// 地形の本番世界は天空の遠方環境を選び、世界名から終端の本数まで連なりが通る。空を描かない起動も同じ検査で
/// 見るのは、`--no-sky`が背景だけを止めて間接照明の方針を動かさないためである。遠方環境はスカイビューの
/// ベイク済み画像を読んで焼くため、空を描かない起動で大気の資源が作られないと束縛する先を失う。
#[test]
fn 地形の本番世界は空を描かなくても遠方環境の連なりを最後まで通る() {
    let 方針 = scene_policy::世界の間接照明方針を決める("terrain_origin");
    assert_eq!(方針, 世界の間接照明方針::天空の遠方環境);
    let 初回の本数 = 間接照明生成パス数::焼いたフレーム(計算で焼く鏡面の段数, true);
    for 空を描く in [true, false] {
        let 結果 = 通す(方針, true, 空を描く).unwrap();
        assert_eq!(結果.契約, 照明問い合わせ契約::遠方環境LambertGGX);
        assert!(結果.大気の資源, "空を描く={空を描く}で大気のベイク済み画像が作られない");
        assert!(結果.遠方環境の資源);
        assert_eq!(結果.初回フレームの本数, 初回の本数);
    }
}

/// 大気の媒体を持たない世界で遠方環境を選ぶと、連なりの最初の段で型付きの失敗になる。
#[test]
fn 大気の媒体が無い世界で遠方環境を選ぶと連なりが立たない() {
    for 空を描く in [true, false] {
        let 誤り = 通す(世界の間接照明方針::天空の遠方環境, false, 空を描く);
        assert!(matches!(誤り, Err(間接照明契約エラー::大気のベイク済み画像なし)));
    }
}
