//! 世界方針から積むパスの本数までを、本番の導出関数の連なりで通す検査。担当するのは「シーン名→世界の
//! 間接照明方針→照明問い合わせ契約→資源の要否→生成パス数の内訳」を1本に繋いで反証することである。
//!
//! 段ごとに分けた検査だけでは足りないことが分かっているためこれを置く。契約の枝と本数の内訳はそれぞれ
//! 単体で反証されていたが、「空を描かない起動では大気のベイク済み画像が作られず遠方環境が焼けない」という
//! 段と段のつなぎ目の不整合はどの単体検査も落とさなかった。
//!
//! GPUを1つも開かないのは、ここで見たいのが資源の中身でなく条件の連なりだからである。

#![allow(clippy::unwrap_used)]

use blitz_engine::sky::世界の間接照明方針;
use blitz_render::distant_environment::間接照明生成パス数;
use blitz_render::indirect_lighting::{照明問い合わせ契約, 間接照明契約エラー};

use super::scene_policy;

/// 鏡面畳込みの既定は6段であり、最詳細段は複製で作るため計算で焼くのは5段である。
const 計算で焼く鏡面の段数: u32 = 5;

/// 連なりを1回通した結果。
struct 連なりの結果 {
    契約: 照明問い合わせ契約,
    大気の資源: bool,
    遠方環境の資源: bool,
    初回フレームの本数: 間接照明生成パス数,
}

/// 本番と同じ導出関数だけを使って、世界の宣言から1フレームの本数までを導く。
fn 通す(
    方針: 世界の間接照明方針, 大気媒体あり: bool, 空を描く: bool
) -> Result<連なりの結果, 間接照明契約エラー> {
    let 契約 = 方針.照明問い合わせ契約へ写す(大気媒体あり)?;
    let 遠方環境の資源 = 契約.遠方環境の資源を作るか();
    Ok(連なりの結果 {
        契約,
        大気の資源: 契約.大気のベイク済み画像を作るか(空を描く),
        遠方環境の資源,
        初回フレームの本数: if 遠方環境の資源 {
            間接照明生成パス数::焼いたフレーム(計算で焼く鏡面の段数, true)
        } else {
            間接照明生成パス数::焼かない()
        },
    })
}

/// 現時点のすべての世界は定数近似であり、空を描く描かないに依らず遠方環境のパスを1本も積まない。
#[test]
fn 既存の世界名はどれも定数近似で本数が0になる() {
    for シーン名 in ["quad", "helmet", "shadow_scene", "fox", "vegetation_4", "terrain_origin"] {
        let 方針 = scene_policy::世界の間接照明方針を決める(シーン名);
        assert_eq!(方針, 世界の間接照明方針::定数近似, "{シーン名}が定数近似でない");
        for 空を描く in [true, false] {
            let 結果 = 通す(方針, true, 空を描く).unwrap();
            assert_eq!(結果.契約, 照明問い合わせ契約::定数近似);
            assert!(!結果.遠方環境の資源, "{シーン名}が遠方環境の資源を作る");
            assert_eq!(結果.初回フレームの本数, 間接照明生成パス数::焼かない(), "{シーン名}がパスを積む");
        }
    }
}

/// 定数近似の世界の大気の資源は空を描くかどうかだけで決まる。既存の判定値が動かないことの土台である。
#[test]
fn 定数近似の大気の資源は空を描くかだけで決まる() {
    assert!(通す(世界の間接照明方針::定数近似, true, true).unwrap().大気の資源);
    assert!(!通す(世界の間接照明方針::定数近似, true, false).unwrap().大気の資源);
}

/// 空を描かない起動でも遠方環境は成立する。大気の資源が作られ、遠方環境の資源も作られ、本数が立つ。
/// この検査が落ちると、地形の本番世界を遠方環境へ切り替えた後に`--no-sky`を渡す検収が起動時に落ちる。
#[test]
fn 空を描かなくても遠方環境の連なりは最後まで通る() {
    let 結果 = 通す(世界の間接照明方針::天空の遠方環境, true, false).unwrap();
    assert_eq!(結果.契約, 照明問い合わせ契約::遠方環境LambertGGX);
    // 遠方環境はスカイビューのベイク済み画像を読んで焼くため、この含意が破れると束縛する先を失う。
    assert!(結果.大気の資源, "空を描かないと大気のベイク済み画像が作られない");
    assert!(結果.遠方環境の資源);
    assert_eq!(結果.初回フレームの本数.遠方環境, 1);
    assert_eq!(結果.初回フレームの本数.最詳細段の複製, 1);
    assert_eq!(結果.初回フレームの本数.拡散照度, 1);
    assert_eq!(結果.初回フレームの本数.鏡面畳込み, 計算で焼く鏡面の段数);
    assert_eq!(結果.初回フレームの本数.反射率積分表, 1);
}

/// 大気の媒体を持たない世界で遠方環境を選ぶと、連なりの最初の段で型付きの失敗になる。
#[test]
fn 大気の媒体が無い世界で遠方環境を選ぶと連なりが立たない() {
    for 空を描く in [true, false] {
        let 誤り = 通す(世界の間接照明方針::天空の遠方環境, false, 空を描く);
        assert!(matches!(誤り, Err(間接照明契約エラー::大気のベイク済み画像なし)));
    }
}
