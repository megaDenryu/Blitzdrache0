//! カメラから空中遠近ボリュームの観測条件を導く工程。担当するのは「カメラ相対ビュー射影の逆変換から視錐台の向きと
//! 最遠距離を求め、方針の観測高度と太陽の向きと束ねて条件を返す」ことである。
//!
//! 視線の向きを「遠平面の点から近平面の点を引いた差」で作るのは、この差がカメラの位置を含まないためである。
//! 位置を含めると大域原点の移動で値が変わり、カメラ相対契約が破れる。差は画面の単位位置についてアフィンであるため、
//! 基準と横縦の差分の3つで厳密に表せる(遠平面も近平面もクリップ座標のwが一定である)。
//!
//! 最遠距離を画面中央の遠平面の点の長さで測るのは、カメラ相対フレームの原点がカメラ自身の大域位置に置かれており、
//! カメラの相対位置が厳密に0だからである(`crate::app::frame::draw_input`の`視点を求める`が決めている)。

use blitz_engine::sky::{スカイビューキー, 天空状態, 空中遠近キー};
use blitz_math::{クリップ, メートル, ワールド, 位置, 変換};
use blitz_render::atmosphere::{単位方向, 空中遠近観測条件, 視錐台の向き};

use crate::app::frame::フレーム視点;

/// 観測条件とその鍵。両方を同じ場所で作るのは、別々に作ると「鍵は変わらないのに条件だけ変わる」食い違いが起こりうるためである。
pub(super) struct 空中遠近の入力 {
    pub(super) 条件: 空中遠近観測条件,
    pub(super) 鍵: 空中遠近キー,
}

pub(super) fn 組む(
    視点: &フレーム視点, 状態: &天空状態, 観測高度: メートル, スカイビュー鍵: スカイビューキー
) -> 空中遠近の入力 {
    // 空中遠近ボリュームの観測条件はずらし無しから導く。ここで導く向きは焼き上げの鍵にもなるため、
    // ずらしで毎フレーム動かすと低い解像度のボリュームを取り直す理由の無い焼き直しが起こる。
    let 逆変換 = 視点.ビュー射影の組.ずらし無し().逆変換する();
    let 遠端 = |横: f32, 縦: f32| 画面の点(&逆変換, 横, 縦, 1.0);
    let 近端 = |横: f32, 縦: f32| 画面の点(&逆変換, 横, 縦, 0.0);
    let 向き = |横: f32, 縦: f32| 引く(遠端(横, 縦), 近端(横, 縦));
    let 基準 = 向き(0.0, 0.0);
    let 横の差分 = 引く(向き(1.0, 0.0), 基準);
    let 縦の差分 = 引く(向き(0.0, 1.0), 基準);
    let 最遠距離 = メートル::生成する(長さ(遠端(0.5, 0.5)));
    let 太陽 = 状態.太陽方向();
    空中遠近の入力 {
        条件: 条件を組む(観測高度, 太陽.成分(), 基準, 横の差分, 縦の差分, 最遠距離),
        鍵: 空中遠近キー::導く(スカイビュー鍵, 太陽, 基準, 横の差分, 縦の差分, 最遠距離),
    }
}

/// 画面の単位位置と深度から、カメラ相対フレームでの点を求める。Vulkanの正規化デバイス座標は縦が下向きであり、
/// 画面の単位位置の縦0が上端に対応する。透視除算は`適用する`が行う。
fn 画面の点(逆変換: &変換<クリップ, ワールド>, 横: f32, 縦: f32, 深度: f32) -> [f32; 3] {
    let クリップ点 = 位置::<クリップ>::生成する(
        メートル::生成する(横 * 2.0 - 1.0),
        メートル::生成する(縦 * 2.0 - 1.0),
        メートル::生成する(深度),
    );
    let 点 = 逆変換.適用する(クリップ点);
    [点.x().値(), 点.y().値(), 点.z().値()]
}

fn 引く(左: [f32; 3], 右: [f32; 3]) -> [f32; 3] {
    [左[0] - 右[0], 左[1] - 右[1], 左[2] - 右[2]]
}

fn 長さ(値: [f32; 3]) -> f32 {
    (値[0] * 値[0] + 値[1] * 値[1] + 値[2] * 値[2]).max(0.0).sqrt()
}

/// 入力は検証済みの方針の観測高度と単位長の太陽方向、それに正則なビュー射影から導いた有限のベクトルである。
/// したがってここでの失敗は不変条件が破れていることを意味し、起動時の設定不備ではないため型付きエラーへは
/// 載せず、破れた不変条件を示して停止する(スカイビューの観測条件と同じ扱い)。
fn 条件を組む(
    観測高度: メートル,
    太陽方向: [f32; 3],
    基準: [f32; 3],
    横の差分: [f32; 3],
    縦の差分: [f32; 3],
    最遠距離: メートル,
) -> 空中遠近観測条件 {
    let 向き =
        視錐台の向き::生成する(基準, 横の差分, 縦の差分).unwrap_or_else(|誤り| panic!("カメラ相対ビュー射影から視錐台の向きを作れなかった: {誤り}"));
    let 太陽 = 単位方向::生成する(太陽方向[0], 太陽方向[1], 太陽方向[2]).unwrap_or_else(|誤り| panic!("太陽方向から単位方向を作れなかった: {誤り}"));
    空中遠近観測条件::生成する(観測高度, 太陽, 向き, 最遠距離).unwrap_or_else(|誤り| panic!("カメラと方針から空中遠近観測条件を作れなかった: {誤り}"))
}
