//! カメラから空中遠近ボリュームの観測条件を導く工程。担当するのは「カメラ相対ビュー射影の逆から導いた視錐台の
//! 向きと最遠距離を、方針の観測高度と太陽の向きと束ねて条件と鍵を返す」ことである。
//!
//! 射影の逆をたどって視錐台の向きと最遠距離を取り出すところは`aerial_frustum`が持つ。深度の端点は逆向き深度の
//! 規約に従うため、その規約を1箇所へ閉じてある。

use blitz_engine::sky::{スカイビューキー, 天空状態, 空中遠近キー};
use blitz_math::メートル;
use blitz_render::atmosphere::{単位方向, 空中遠近観測条件, 視錐台の向き};

use super::aerial_frustum::視錐台の向きと最遠距離;
use crate::app::frame::フレーム視点;

/// 観測条件とその鍵。両方を同じ場所で作るのは、別々に作ると「鍵は変わらないのに条件だけ変わる」食い違いが起こりうるためである。
pub(super) struct 空中遠近の入力 {
    pub(super) 条件: 空中遠近観測条件,
    pub(super) 鍵: 空中遠近キー,
}

pub(super) fn 組む(
    視点: &フレーム視点, 状態: &天空状態, 観測高度: メートル, スカイビュー鍵: スカイビューキー
) -> 空中遠近の入力 {
    // 空中遠近ボリュームの観測条件はずらし無しから導く。ここで導く向きは焼き上げの鍵にもなるため、
    // ずらしで毎フレーム動かすと低い解像度のボリュームを取り直す理由の無い焼き直しが起こる。
    let 逆変換 = 視点.ビュー射影の組.ずらし無し().逆変換する();
    let 視錐台 = 視錐台の向きと最遠距離::カメラ相対ビュー射影の逆から導く(&逆変換);
    let 太陽 = 状態.太陽方向();
    空中遠近の入力 {
        条件: 条件を組む(観測高度, 太陽.成分(), &視錐台),
        鍵: 空中遠近キー::導く(スカイビュー鍵, 太陽, 視錐台.基準, 視錐台.横の差分, 視錐台.縦の差分, 視錐台.最遠距離),
    }
}

/// 入力は検証済みの方針の観測高度と単位長の太陽方向、それに正則なビュー射影から導いた有限のベクトルである。
/// したがってここでの失敗は不変条件が破れていることを意味し、起動時の設定不備ではないため型付きエラーへは
/// 載せず、破れた不変条件を示して停止する(スカイビューの観測条件と同じ扱い)。
fn 条件を組む(観測高度: メートル, 太陽方向: [f32; 3], 視錐台: &視錐台の向きと最遠距離) -> 空中遠近観測条件 {
    let 向き = 視錐台の向き::生成する(視錐台.基準, 視錐台.横の差分, 視錐台.縦の差分)
        .unwrap_or_else(|誤り| panic!("カメラ相対ビュー射影から視錐台の向きを作れなかった: {誤り}"));
    let 太陽 = 単位方向::生成する(太陽方向[0], 太陽方向[1], 太陽方向[2]).unwrap_or_else(|誤り| panic!("太陽方向から単位方向を作れなかった: {誤り}"));
    空中遠近観測条件::生成する(観測高度, 太陽, 向き, 視錐台.最遠距離)
        .unwrap_or_else(|誤り| panic!("カメラと方針から空中遠近観測条件を作れなかった: {誤り}"))
}
