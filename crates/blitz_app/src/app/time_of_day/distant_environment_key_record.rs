//! 遠方環境の焼き直し判定が何を見て何を答えたかの記録。触れる状態は数えた回数2つと直近の鍵1つだけであり、
//! 判定そのものには関わらない。
//!
//! これを置くのは、太陽円盤の明るさだけを変えた対で「鍵も焼き直しの判断も1つも動かない」ことを機械判定するためである。
//! 遠方環境の中身は鍵が決めるため(鍵の構成要素がそのまま焼き上げの即時定数になる)、鍵が対で同じであることは
//! 焼いた立方体画像が対で同じであることを意味する。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Ic-3bの実装」

use blitz_engine::sky::遠方環境キー;
use blitz_render::distant_environment::input::遠方環境の生成指示;

pub(crate) struct 遠方環境の鍵の記録 {
    判定したフレーム数: u64,
    焼き直すと判断したフレーム数: u64,
    直近の鍵: Option<遠方環境キー>,
}

impl 遠方環境の鍵の記録 {
    pub(crate) fn 新規() -> Self {
        Self {
            判定したフレーム数: 0,
            焼き直すと判断したフレーム数: 0,
            直近の鍵: None,
        }
    }

    pub(crate) fn 記録する(&mut self, 鍵: 遠方環境キー, 指示: 遠方環境の生成指示) {
        self.判定したフレーム数 += 1;
        if 指示 == 遠方環境の生成指示::焼き直す {
            self.焼き直すと判断したフレーム数 += 1;
        }
        self.直近の鍵 = Some(鍵);
    }

    pub(crate) fn 判定したフレーム数(&self) -> u64 {
        self.判定したフレーム数
    }

    pub(crate) fn 焼き直すと判断したフレーム数(&self) -> u64 {
        self.焼き直すと判断したフレーム数
    }

    /// 直近に判定した鍵の表記。鍵の中身は値の比較でしか意味を持たないため、成分を並べ直さずデバッグ表記を
    /// そのまま出し、対の間で1つの文字列として比べる。1度も判定していない実行は「なし」を返す。
    pub(crate) fn 直近の鍵の表記(&self) -> String {
        match &self.直近の鍵 {
            Some(鍵) => format!("{鍵:?}"),
            None => "なし".to_string(),
        }
    }
}
