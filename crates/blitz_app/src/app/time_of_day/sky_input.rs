//! 天空状態と空入力を組み立てる工程。受け取るのは空と太陽の方針と世界時刻、返すのはその時刻の天空状態と空入力である。
//!
//! 空入力は視点にもフレームにも依存しないため、時刻が動いたときだけ作り直せばよい。
//! 夜空放射輝度・太陽円盤・観測高度・太陽放射照度は時刻に依らない空描画方針の値であり、時刻から来るのは太陽の向きだけである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「空の方式」

use std::fmt::Display;

use blitz_engine::sky::{天空状態, 天空状態を導出する, 空と太陽の方針};
use blitz_engine::time::世界時刻;
use blitz_render::{空入力, 空入力の材料};

pub(super) fn 天空状態を導く(方針: &空と太陽の方針, 時刻: 世界時刻) -> 天空状態 {
    確定値(天空状態を導出する(時刻, 方針))
}

pub(super) fn 空入力を作る(状態: &天空状態, 方針: &空と太陽の方針) -> 空入力 {
    let 描画 = 方針.空描画();
    確定値(空入力::生成する(空入力の材料 {
        夜空放射輝度: 描画.夜空放射輝度().成分(),
        太陽方向: 状態.太陽方向().成分(),
        太陽円盤放射輝度: 描画.太陽円盤放射輝度().成分(),
        太陽円盤角半径: 描画.太陽円盤角半径(),
        観測高度: 描画.観測高度(),
        太陽放射照度: 描画.太陽放射照度(),
    }))
}

/// 入力は値域を検証済みの方針と有限の世界時刻だけであるため、ここでの失敗は導出の不変条件が破れていることを意味する。
/// 起動時の設定不備ではないため型付きエラーへは載せず、破れた不変条件を示して停止する
/// (`scene_lighting`の検収用ライト方針と同じ扱い)。
fn 確定値<T, E: Display>(結果: Result<T, E>) -> T {
    結果.unwrap_or_else(|誤り| panic!("空入力の組み立てで不変条件が破れた: {誤り}"))
}
