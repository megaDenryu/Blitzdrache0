//! 空入力を組み立てる工程。受け取るのは世界の空方針、返すのはレンダラーへ毎フレーム渡す空入力である。
//!
//! 時刻は世界の空方針が持つ既定時刻を使う。時計の進行と、方向光・環境光・露出を同じ天空状態へ配線することは
//! 続く段が行うため、ここは空パスが要る係数だけを1つの時刻から作る。
//! 空入力は視点にもフレームにも依存しないため、起動時に1度だけ作って毎フレーム同じ値を渡す。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「空の方式」

use std::fmt::Display;

use blitz_engine::sky::{世界の空方針, 天空状態を導出する, 空放射輝度係数};
use blitz_render::空入力;

pub(in crate::app) fn 既定時刻の空入力を作る(方針: 世界の空方針) -> Option<空入力> {
    let 世界の空方針::空あり { 空と太陽, 既定時刻 } = 方針 else {
        return None;
    };
    let 状態 = 確定値(天空状態を導出する(既定時刻, &空と太陽));
    let 係数 = 確定値(空放射輝度係数::導出する(&状態, &空と太陽));
    Some(確定値(空入力::生成する(
        係数.方向係数(),
        係数.放射輝度スケール(),
        係数.夜空放射輝度().成分(),
        係数.昼係数().値(),
        状態.太陽方向().成分(),
        係数.太陽円盤放射輝度().成分(),
        係数.太陽円盤角半径(),
    )))
}

/// 入力は値域を検証済みの方針と有限の世界時刻だけであるため、ここでの失敗は導出の不変条件が破れていることを意味する。
/// 起動時の設定不備ではないため型付きエラーへは載せず、破れた不変条件を示して停止する
/// (`scene_lighting`の検収用ライト方針と同じ扱い)。
fn 確定値<T, E: Display>(結果: Result<T, E>) -> T {
    結果.unwrap_or_else(|誤り| panic!("空入力の組み立てで不変条件が破れた: {誤り}"))
}
