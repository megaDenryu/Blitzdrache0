//! 遠方環境の1フレーム入力を組む工程。担当するのは「大気静的キーと天空状態と空描画方針から、代表天頂余弦で
//! 正規化した遠方環境キーと観測条件を導き、そのフレームの生成指示と一緒に1つの入力へまとめる」ことである。
//! 受け取るのは材料と更新判定と間引き、返すのはレンダラーへ渡す入力である。
//!
//! 大気の入力と別の工程にするのは、正規化するかどうかが違うためである。大気のベイク済み画像は時計の進行で
//! 毎フレーム動く連続な天頂余弦で焼き、遠方環境だけが区間の代表値で焼く。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」

use blitz_engine::sky::atmosphere::大気静的キー;
use blitz_engine::sky::{スカイビューキー, 天空状態, 空描画方針, 遠方環境キー};
use blitz_render::atmosphere::天空放射輝度の尺度;
use blitz_render::distant_environment::{ワールドの太陽方向, 遠方環境の入力};

use super::atmosphere_input::{スカイビュー条件を組む, 太陽天頂余弦を読む};
use super::distant_environment_update::遠方環境更新判定;
use super::thinning::遠方環境の間引き;

/// 入力を組むのに要る材料。引数の列が伸び続けるのを避けて1つに束ねる。
pub(super) struct 遠方環境入力の材料<'a> {
    pub(super) 大気の静的キー: 大気静的キー,
    pub(super) 空描画: 空描画方針,
    pub(super) 状態: &'a 天空状態,
}

/// 明るさの尺度は空描画方針が正本であり、鍵はスカイビューキーへその2つを足したものである。
///
/// スカイビューキーを大気の入力と共有せずここで作り直すのは、遠方環境だけが太陽の天頂余弦を代表天頂余弦へ
/// 正規化するためである。区間の中では代表値が動かないため鍵も動かず、既存の値の比較がそのまま間引きになる。
/// 太陽円盤放射輝度を鍵へ入れないのは、遠方環境が円盤を除いた連続な天空放射輝度だけを保持するためである。
/// 太陽方向を鍵と別に運ぶのは、焼き上げが太陽相対座標で行われ、この向きが焼いた内容を1つも変えないためである(参照: `_doc/設計/放射輝度問い合わせ階層.md`「鍵の設計(2つの注意)」)。
pub(super) fn 組む(
    材料: &遠方環境入力の材料<'_>, 判定: &mut 遠方環境更新判定, 間引き: &mut 遠方環境の間引き
) -> 遠方環境の入力 {
    let 区間 = 間引き.区間を決める(太陽天頂余弦を読む(材料.状態));
    let 代表 = 区間.代表天頂余弦().値();
    let 観測高度 = 材料.空描画.観測高度();
    let スカイビュー鍵 = スカイビューキー::導く(材料.大気の静的キー, 代表, 観測高度);
    let 鍵 = 遠方環境キー::導く(スカイビュー鍵, 材料.空描画.太陽放射照度(), 材料.空描画.夜空放射輝度());
    遠方環境の入力::生成する(
        尺度を組む(材料.空描画),
        太陽方向を写す(材料.状態),
        スカイビュー条件を組む(観測高度, 代表),
        判定.判定する(鍵),
    )
}

/// 天空状態の太陽方向をレンダラーの語彙へ写す。天空状態の太陽方向は生成時に正規化済みであり、
/// ここでの失敗は写しが不変条件を運べていないことを意味するため、破れた不変条件を示して停止する。
fn 太陽方向を写す(状態: &天空状態) -> ワールドの太陽方向 {
    let [東, 天頂, 南] = 状態.太陽方向().成分();
    ワールドの太陽方向::生成する(東, 天頂, 南).unwrap_or_else(|誤り| panic!("天空状態の太陽方向からワールドの太陽方向を作れなかった: {誤り}"))
}

/// 空描画方針の2つの値を天空放射輝度の尺度へ写す。方針の生成が有限性と符号を検証済みのため、ここでの失敗は
/// 写しが不変条件を運べていないことを意味し、破れた不変条件を示して停止する。
fn 尺度を組む(空描画: 空描画方針) -> 天空放射輝度の尺度 {
    天空放射輝度の尺度::生成する(空描画.太陽放射照度(), 空描画.夜空放射輝度().成分())
        .unwrap_or_else(|誤り| panic!("空描画方針から天空放射輝度の尺度を作れなかった: {誤り}"))
}
