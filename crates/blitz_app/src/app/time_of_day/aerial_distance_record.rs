//! 本番の空中遠近条件が実際に持った最遠距離の記録。触れる状態は数えたフレーム数と最小と最大だけであり、
//! 焼き直しの判定には関わらない。
//!
//! これを置くのは、逆向き深度の端点を取り違えたときに最遠距離が遠クリップから近クリップへ落ちるためである。
//! 落ちても絵は8ビットの読み戻しでほとんど変わらず、絵の照合では捕まらない。焼きへ渡った数そのものを報告し、
//! 検収が遠クリップとの一致を課す。
//!
//! 最小と最大の両方を持つのは、実行の途中で1フレームだけ別の距離が混じった場合も落とすためである。
//! 1度も組んでいない実行では距離そのものが無いため、マジック値でなく`None`で表す。

use blitz_math::メートル;

pub(crate) struct 空中遠近の最遠距離の記録 {
    組んだフレーム数: u64,
    最小: Option<メートル>,
    最大: Option<メートル>,
}

impl 空中遠近の最遠距離の記録 {
    pub(in crate::app) fn 新規() -> Self {
        Self {
            組んだフレーム数: 0,
            最小: None,
            最大: None,
        }
    }

    pub(in crate::app) fn 記録する(&mut self, 最遠距離: メートル) {
        self.組んだフレーム数 += 1;
        self.最小 = Some(小さい方(self.最小, 最遠距離));
        self.最大 = Some(大きい方(self.最大, 最遠距離));
    }

    pub(crate) fn 組んだフレーム数(&self) -> u64 {
        self.組んだフレーム数
    }

    /// 実行の全フレームで最も短かった最遠距離。1度も条件を組んでいない実行では無い。
    pub(crate) fn 最小(&self) -> Option<メートル> {
        self.最小
    }

    pub(crate) fn 最大(&self) -> Option<メートル> {
        self.最大
    }
}

fn 小さい方(これまで: Option<メートル>, 新しい距離: メートル) -> メートル {
    match これまで {
        Some(既存) if 既存.値() <= 新しい距離.値() => 既存,
        _ => 新しい距離,
    }
}

fn 大きい方(これまで: Option<メートル>, 新しい距離: メートル) -> メートル {
    match これまで {
        Some(既存) if 既存.値() >= 新しい距離.値() => 既存,
        _ => 新しい距離,
    }
}
