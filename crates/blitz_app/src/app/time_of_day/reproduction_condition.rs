//! 空代表画素の照合に要る、そのフレームの空の状態をまとめた型。担当するのは「大気・太陽方向・空描画方針の
//! 3つを1つの値として運ぶ」ことであり、空を持つ世界が大気のベイク済み画像を持つときだけ組み立てられる。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「検証の設計」

use blitz_engine::sky::空描画方針;
use blitz_render::atmosphere::大気散乱媒体;

#[derive(Clone, Copy)]
pub(crate) struct 空の再現条件 {
    pub(crate) 大気: 大気散乱媒体,
    pub(crate) 太陽方向: [f32; 3], // 地表から太陽へ向かう単位ベクトル。Xが東、Yが天頂、Zが南である
    pub(crate) 空描画: 空描画方針,
}
