//! 自動露出の時間適応へ渡す経過秒の供給元。担当するのは「そのフレームの経過秒を1つ答える」ことだけであり、
//! 露出の値も補正段も知らない。
//!
//! 実時間と固定の刻みを型の枝で分けるのは、2つが両立しないためである。適応速度は「補正段毎秒」であり、
//! 本番は実時間で進まなければ毎秒の意味が保てない。一方、読み戻した画像や補正段のバイト一致を見る検収は、
//! 実行ごとに揺れる実時間では成立しない。どちらを使うかは実行の種類が決め、フレームごとの判断は持たない。

use std::time::Instant;

use crate::cli::起動モード;

/// 決められたフレーム数で終わる実行が使う刻み。毎秒60フレーム相当であり、アニメーション時刻の固定歩進(判断47)と同じ値である。
const 検収の固定の刻み秒: f32 = 1.0 / 60.0;
/// 実時間の1フレームに認める上限。デバッガでの停止やウィンドウの移動で実時間が大きく飛んだとき、
/// その1フレームで補正段が何段も動くのを止める。4フレーム毎秒より長い停止は打ち切りとして扱う。
const 実時間の上限秒: f32 = 0.25;

enum 刻みの決め方 {
    /// 本番。前フレームからの実時間を使い、上限で頭打ちにする。最初のフレームは基準が無いため0秒である。
    実フレーム時間 { 前回の実時刻: Option<Instant> },
    /// 検収。実時間を1度も読まず、同じ刻みを毎フレーム答える。
    固定の刻み,
}

/// 決め方と、そのフレームぶんの答えを保つ。答えを保つのは、時刻を読む地点(フレームの世界更新)と
/// 値を使う地点(描画入力の組み立て)が分かれており、1フレームに2度読むと2つの経過秒ができるためである。
pub(in crate::app) struct 自動露出の経過秒源 {
    決め方: 刻みの決め方,
    このフレームの経過秒: f32,
}

impl 自動露出の経過秒源 {
    /// フレーム数の決まった実行(スモーク・ベンチ)は固定の刻み、無期限実行は実時間を使う。
    /// フレーム数が決まっている実行はどれも成果物の決定性を前提にしており、そこへ実時間を持ち込むと
    /// 読み戻した絵のバイト一致がすべて揺れる。
    pub(in crate::app) fn 起動モードから決める(モード: 起動モード) -> Self {
        let 決め方 = match モード {
            起動モード::無期限実行 => 刻みの決め方::実フレーム時間 { 前回の実時刻: None },
            起動モード::スモーク実行 { .. } | 起動モード::ベンチ実行 { .. } | 起動モード::段差走査実行 { .. } => {
                刻みの決め方::固定の刻み
            }
        };
        Self {
            決め方,
            このフレームの経過秒: 0.0,
        }
    }

    /// フレームの世界更新で1度だけ呼ぶ。実時間の枝はここでだけ時刻を読む。
    pub(in crate::app) fn 進める(&mut self) {
        let 刻みの決め方::実フレーム時間 { 前回の実時刻 } = &mut self.決め方 else {
            self.このフレームの経過秒 = 検収の固定の刻み秒;
            return;
        };
        let 今 = Instant::now();
        let 経過 = 前回の実時刻.map_or(0.0, |前| 今.duration_since(前).as_secs_f32());
        *前回の実時刻 = Some(今);
        self.このフレームの経過秒 = 経過.min(実時間の上限秒);
    }

    pub(in crate::app) fn このフレームの経過秒(&self) -> f32 {
        self.このフレームの経過秒
    }
}
