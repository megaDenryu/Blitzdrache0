//! エンジンの大気媒体方針をレンダラーの大気散乱媒体へ下ろす工程。受け取るのは方針、返すのはLUT生成の入力である。
//!
//! 2つのクレートが同じ物理量を別々の型で持つのは、`blitz_render`が上位のエンジン層へ依存しないという封じ込めの規律による。
//! その規律の代償として同じ値の組を2度組み立てられてしまうため、写す場所をコンポジションルートのこの1箇所に閉じる。
//! 密度分布を尺度高度から組み直さず層の係数をそのまま写すのは、両側の導出が将来食い違っても写しの側が方針に従うようにするためである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「大気LUT方式の設計(第7段で実装する)」

use blitz_engine::sky::atmosphere::{大気媒体方針, 密度分布, 密度分布層, 消散係数RGB};
use blitz_render::atmosphere::{
    位相非対称係数, 地表アルベドRGB, 大気散乱媒体, 大気数学エラー, 密度分布 as 描画密度分布, 密度分布層 as 描画密度分布層,
    消散係数RGB as 描画消散係数RGB, 消散媒体, 減衰成分,
};

pub(in crate::app) fn 大気散乱媒体へ写す(方針: &大気媒体方針) -> Result<大気散乱媒体, 大気数学エラー> {
    let レイリー = 方針.レイリー();
    let ミー = 方針.ミー();
    let 吸収 = 方針.吸収();
    let 消散 = 消散媒体::生成する(
        方針.惑星形状().下端半径(),
        方針.惑星形状().上端半径(),
        減衰成分::生成する(係数を写す(レイリー.消散係数())?, 分布を写す(レイリー.密度分布())?),
        減衰成分::生成する(係数を写す(ミー.消散係数())?, 分布を写す(ミー.密度分布())?),
        減衰成分::生成する(係数を写す(吸収.消散係数())?, 分布を写す(吸収.密度分布())?),
    )?;
    let [赤, 緑, 青] = 方針.地表アルベド().成分();
    大気散乱媒体::生成する(
        消散,
        係数を写す(レイリー.散乱係数())?,
        係数を写す(ミー.散乱係数())?,
        位相非対称係数::生成する(ミー.位相非対称係数().値())?,
        地表アルベドRGB::生成する(赤, 緑, 青)?,
    )
}

fn 係数を写す(係数: 消散係数RGB) -> Result<描画消散係数RGB, 大気数学エラー> {
    let [赤, 緑, 青] = 係数.成分();
    描画消散係数RGB::生成する(赤, 緑, 青)
}

fn 分布を写す(分布: 密度分布) -> Result<描画密度分布, 大気数学エラー> {
    let [第1層, 第2層] = 分布.層();
    Ok(描画密度分布::生成する(層を写す(第1層)?, 層を写す(第2層)?))
}

fn 層を写す(層: 密度分布層) -> Result<描画密度分布層, 大気数学エラー> {
    描画密度分布層::生成する(層.幅(), 層.指数項(), 層.指数尺度(), 層.線形項(), 層.定数項())
}
