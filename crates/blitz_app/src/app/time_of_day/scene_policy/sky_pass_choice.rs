//! そのフレームへ空パスを積むかどうかの判定。受け取るのはその世界の空方針と起動指定、返すのは積むかどうかである。
//!
//! 世界が何を選ぶかを決める親モジュールと分けるのは、答える問いが違うためである。親は「その世界は空を持つか」を
//! 世界の性格から決め、ここは持つと決まった世界について「この実行はその空を描くか」を起動指定と突き合わせて決める。

use blitz_engine::sky::世界の空方針;

use crate::cli::空の起動指定;

/// 方針が空ありでも`--no-sky`は積まない。方針が空なしのとき、`--sky`は方針そのものを空ありへ上書き済みである。
pub(in crate::app) fn 空パスを積むか(方針: 世界の空方針, 指定: 空の起動指定) -> bool {
    match (方針, 指定) {
        (_, 空の起動指定::空を描かない) | (世界の空方針::空なし, _) => false,
        (世界の空方針::空あり { .. }, _) => true,
    }
}
