//! 世界の種別から、方針が参照する3つの分類を答える工程。受け取るのは世界の種別、返すのは
//! 「大気の媒体を持つか」と「地形チャンクを敷くか」と「履歴混合を受ける地形世界か」の3つである。
//!
//! どちらも網羅`match`で書くのは、世界を1つ足したときに、その世界が大気を持つのかと地形を敷くのかを
//! 書き手に必ず決めさせるためである。`matches!`や接頭辞の比較では、足した世界が黙って既定側へ落ちる。

use crate::cli::{世界の種別, 地形世界の種別};

/// 大気の媒体を持つ世界か。地形チャンクを敷く世界と、遠方環境の消費を機械判定する検収世界がこれに当たる。
pub(super) fn 大気の媒体を持つ世界か(種別: 世界の種別) -> bool {
    match 種別 {
        世界の種別::地形世界(_) | 世界の種別::間接照明の検収世界 => true,
        世界の種別::平面板
        | 世界の種別::ヘルメット
        | 世界の種別::影の検収世界
        | 世界の種別::キツネ
        | 世界の種別::材質差し替えの検収世界
        | 世界の種別::両視錐台外の群の検収世界
        | 世界の種別::二材質の検収世界
        | 世界の種別::テクスチャ圧縮の検収世界
        | 世界の種別::植生の検収世界(_)
        | 世界の種別::小物世界(_)
        | 世界の種別::名前で選ばれない世界 => false,
    }
}

/// 地形チャンクを敷く世界か。露出方式・拡散間接方式・時間再構成方式の3つがこの分類で分かれる。
pub(super) fn 地形チャンクを敷く世界か(種別: 世界の種別) -> bool {
    match 種別 {
        世界の種別::地形世界(_) => true,
        世界の種別::平面板
        | 世界の種別::ヘルメット
        | 世界の種別::影の検収世界
        | 世界の種別::キツネ
        | 世界の種別::材質差し替えの検収世界
        | 世界の種別::間接照明の検収世界
        | 世界の種別::両視錐台外の群の検収世界
        | 世界の種別::二材質の検収世界
        | 世界の種別::テクスチャ圧縮の検収世界
        | 世界の種別::植生の検収世界(_)
        | 世界の種別::小物世界(_)
        | 世界の種別::名前で選ばれない世界 => false,
    }
}

/// 履歴混合を受ける地形世界か。動くキツネを持つ世界を外す理由は`世界の時間再構成方式を決める`が述べる。
pub(super) fn 履歴混合を受ける地形世界か(種別: 世界の種別) -> bool {
    let 世界の種別::地形世界(地形の種別) = 種別 else {
        return false;
    };
    match 地形の種別 {
        地形世界の種別::起点 | 地形世界の種別::目視見本 | 地形世界の種別::夜灯り | 地形世界の種別::名前で選ばれない地形 => {
            true
        }
        地形世界の種別::場所巡り | 地形世界の種別::エディター => false,
    }
}
