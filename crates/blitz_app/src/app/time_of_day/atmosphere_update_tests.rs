//! 大気更新判定が鍵の層ごとの違いを正しい指示へ分類することの検査。
//!
//! 太陽の高度が同じまま方位だけが変わるフレームを見る。この場合はスカイビューLUTが前フレームのまま正しく、
//! 空中遠近ボリュームだけが変わるため、指示は「空中遠近だけ焼き直す」でなければならない。
//! 鍵が太陽の方位を落としていると「前の結果を使う」が返り、古いボリュームを引き続ける。

#![allow(clippy::unwrap_used)]

use blitz_engine::sky::atmosphere::大気媒体方針;
use blitz_engine::sky::{スカイビューキー, 太陽方向, 空中遠近キー};
use blitz_math::メートル;
use blitz_render::atmosphere_lut_input::大気LUT生成指示;

use super::atmosphere_update::大気更新判定;

/// カメラの視錐台と最遠距離と観測高度を固定し、太陽の向きだけを変えて鍵を作る。
fn 太陽の向きだけを変えた鍵(太陽: 太陽方向) -> 空中遠近キー {
    let スカイビュー = スカイビューキー::導く(大気媒体方針::地球標準().静的キー(), 太陽.成分()[1], メートル::生成する(2.0));
    空中遠近キー::導く(
        スカイビュー,
        太陽,
        [0.0, 0.0, -1.0],
        [1.6, 0.0, 0.0],
        [0.0, -0.9, 0.0],
        メートル::生成する(2000.0),
    )
}

#[test]
fn 太陽の高度が同じで方位が変わったフレームは空中遠近だけを焼き直す() {
    let 東 = 太陽方向::生成する(0.6, 0.8, 0.0).unwrap();
    let 西 = 太陽方向::生成する(-0.6, 0.8, 0.0).unwrap();
    let mut 判定 = 大気更新判定::新規();
    assert_eq!(判定.判定する(太陽の向きだけを変えた鍵(東)), 大気LUT生成指示::全部焼き直す);
    assert_eq!(判定.判定する(太陽の向きだけを変えた鍵(西)), 大気LUT生成指示::空中遠近だけ焼き直す);
}

/// 何も動かないフレームが前の結果を使うことを合わせて固定する。上の検査だけでは「常に空中遠近を焼く」実装も通る。
#[test]
fn 何も動かないフレームは前の結果を使う() {
    let 太陽 = 太陽方向::生成する(0.6, 0.8, 0.0).unwrap();
    let mut 判定 = 大気更新判定::新規();
    assert_eq!(判定.判定する(太陽の向きだけを変えた鍵(太陽)), 大気LUT生成指示::全部焼き直す);
    assert_eq!(判定.判定する(太陽の向きだけを変えた鍵(太陽)), 大気LUT生成指示::前の結果を使う);
}

/// 太陽の高度が変わったフレームはスカイビューも焼き直す。方位を足したことで層の分類が崩れていないことを見る。
#[test]
fn 太陽の高度が変わったフレームはスカイビューと空中遠近を焼き直す() {
    let 低い = 太陽方向::生成する(0.6, 0.8, 0.0).unwrap();
    let 高い = 太陽方向::生成する(0.0, 1.0, 0.0).unwrap();
    let mut 判定 = 大気更新判定::新規();
    assert_eq!(判定.判定する(太陽の向きだけを変えた鍵(低い)), 大気LUT生成指示::全部焼き直す);
    assert_eq!(
        判定.判定する(太陽の向きだけを変えた鍵(高い)),
        大気LUT生成指示::スカイビューと空中遠近を焼き直す
    );
}
