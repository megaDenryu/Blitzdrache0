//! 1回の起動が何を撮るかの指定。担うのは「一日の跨ぎの一覧のどこを撮るか」と、そこから決まる実行のフレーム数
//! だけである。撮影の中身も出力先も知らない。
//!
//! 一日ぶんを1回の起動で撮らずに範囲で切るのは、1撮影が読み戻す圧縮前のHDRが1枚あたり十数メガバイトあり、
//! 一日ぶん(跨ぎ326件の対で652枚)を残したままにすると数十ギガバイトを占めるためである。検収は範囲ごとに
//! 起動し、読み終えた生の画像を捨てながら進む。
//!
//! 対照を別の枝にするのは、撮る枚数も並びも範囲と違うためである。範囲は跨ぎごとに下側と上側の対を撮り、
//! 対照は1つの跨ぎで下側・上側・下側の3枚を撮る。真偽値を範囲へ足すと、対照のときの件数が意味を持たない値になる。

use crate::cli::起動引数エラー;

/// 1つの撮影で描くフレーム数。最後の1フレームで読み戻す。
///
/// 先に1フレーム描くのは、時刻と区間を据え直した最初のフレームが遠方環境の焼き直しを含むためである。
/// 焼き直しと消費は同じフレームで完結するが、資源の更新を1つも挟まないフレームを読むほうが、
/// 対の2枚が同じ条件で撮られたことを説明しやすい。
pub(super) const 一撮影のフレーム数: u32 = 2;

/// 1つの跨ぎで撮る枚数。跨ぎの下側の区間と上側の区間の対である。
const 一跨ぎの撮影数: u32 = 2;

/// 対照で撮る枚数。下側・上側・下側の3枚である。
const 対照の撮影数: u32 = 3;

/// 1回の起動が撮るもの。番号は`--report-sun-zenith-crossings`が出す一覧の並び順である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 段差走査の指定 {
    範囲 { 最初の跨ぎ番号: u16, 跨ぎの件数: u16 }, // 跨ぎの範囲。跨ぎごとに下側と上側の対を撮る
    対照 { 跨ぎ番号: u16 },                        // 1つの跨ぎの対照。下側・上側・下側の順に3枚撮り、1枚目と3枚目の一致で状態の持ち越しを反証する
}

impl 段差走査の指定 {
    /// 件数0を拒むのは、1件も撮らない実行が0フレームで終わり、絵を1枚も残さないまま成功を返すためである。
    pub(crate) fn 範囲を作る(最初の跨ぎ番号: u16, 跨ぎの件数: u16) -> Result<Self, 起動引数エラー> {
        if 跨ぎの件数 == 0 {
            return Err(起動引数エラー::段差走査範囲不正("跨ぎの件数が0である".to_string()));
        }
        Ok(Self::範囲 {
            最初の跨ぎ番号, 跨ぎの件数
        })
    }

    pub(crate) fn 最初の跨ぎ番号(self) -> u16 {
        match self {
            Self::範囲 { 最初の跨ぎ番号, .. } => 最初の跨ぎ番号,
            Self::対照 { 跨ぎ番号 } => 跨ぎ番号,
        }
    }

    pub(crate) fn 跨ぎの件数(self) -> u16 {
        match self {
            Self::範囲 { 跨ぎの件数, .. } => 跨ぎの件数,
            Self::対照 { .. } => 1,
        }
    }

    /// この指定を撮り終えるまでのフレーム数。実行の終了条件がこの値から決まる。
    pub(crate) fn 総フレーム数(self) -> u32 {
        let 撮影数 = match self {
            Self::範囲 { 跨ぎの件数, .. } => u32::from(跨ぎの件数) * 一跨ぎの撮影数,
            Self::対照 { .. } => 対照の撮影数,
        };
        撮影数 * 一撮影のフレーム数
    }
}
