//! 1回の起動で撮る境界の範囲。担うのは「一日の境界一覧のどこから何本撮るか」と、その本数から決まる
//! 実行のフレーム数だけである。撮影の中身も出力先も知らない。
//!
//! 一日ぶんを1回の起動で撮らずに範囲で切るのは、1撮影が読み戻す圧縮前のHDRが1枚あたり十数メガバイトあり、
//! 一日ぶん(境界163本の対で326枚)を残したままにすると数ギガバイトを占めるためである。検収は範囲ごとに
//! 起動し、読み終えた生の画像を捨てながら進む。

use crate::cli::起動引数エラー;

/// 1つの撮影で描くフレーム数。最後の1フレームで圧縮前のHDRを読み戻す。
///
/// 先に1フレーム描くのは、時刻と区間を据え直した最初のフレームが遠方環境の焼き直しを含むためである。
/// 焼き直しと消費は同じフレームで完結するが、資源の更新を1つも挟まないフレームを読むほうが、
/// 対の2枚が同じ条件で撮られたことを説明しやすい。
pub(super) const 一撮影のフレーム数: u32 = 2;

/// 1つの境界で撮る枚数。境界の下側の区間と上側の区間の対である。
const 一境界の撮影数: u32 = 2;

/// 撮る境界の範囲。番号は`--report-sun-zenith-boundaries`が出す一覧の並び順である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 段差走査範囲 {
    最初の境界番号: u16,
    境界の本数: u16,
}

impl 段差走査範囲 {
    /// 本数0を拒むのは、1本も撮らない実行が0フレームで終わり、絵を1枚も残さないまま成功を返すためである。
    pub(crate) fn 生成する(最初の境界番号: u16, 境界の本数: u16) -> Result<Self, 起動引数エラー> {
        if 境界の本数 == 0 {
            return Err(起動引数エラー::段差走査範囲不正("境界の本数が0である".to_string()));
        }
        Ok(Self {
            最初の境界番号, 境界の本数
        })
    }

    pub(crate) fn 最初の境界番号(self) -> u16 {
        self.最初の境界番号
    }

    pub(crate) fn 境界の本数(self) -> u16 {
        self.境界の本数
    }

    /// この範囲を撮り終えるまでのフレーム数。実行の終了条件がこの値から決まる。
    pub(crate) fn 総フレーム数(self) -> u32 {
        u32::from(self.境界の本数) * 一境界の撮影数 * 一撮影のフレーム数
    }
}
