//! この描画が段差の走査の撮影の中にあるかどうかの答え。担当するのは、天空配線が段差走査から読んだ結果を、
//! 検収の経路の判定へ渡せる形で運ぶことだけである。走査を持たない実行では常に撮っていない。
//!
//! 「撮っている」が撮影の指定と読み戻すかどうかを一緒に持つのは、書き出し先の名前が撮影の側から決まり、
//! 読み戻すかどうかが撮影の最後のフレームかどうかから決まるという2つが、常に揃って判定へ渡るためである。

use super::shot::撮影指定;

/// この描画と段差の走査の撮影の関係。
#[derive(Debug, Clone, Copy)]
pub(in crate::app) enum 撮影の有無 {
    撮っていない,                                                // 段差の走査でない実行、または撮り終えた後のフレーム
    撮っている { 撮影: 撮影指定, このフレームで読み戻す: bool }, // 撮影の中のフレーム。最後のフレームだけが読み戻して書き出す
}
