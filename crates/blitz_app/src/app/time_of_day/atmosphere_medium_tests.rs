//! 下ろし変換が方針の値をそのまま運ぶことの検査。値が1つでも入れ替わるとLUTの色が静かにずれるため、成分ごとに固定する。

#![allow(clippy::unwrap_used)]

use blitz_engine::sky::atmosphere::大気媒体方針;
use blitz_render::atmosphere::大気散乱媒体;

use super::atmosphere_medium::大気散乱媒体へ写す;

fn 地球標準の媒体() -> 大気散乱媒体 {
    大気散乱媒体へ写す(&大気媒体方針::地球標準()).unwrap()
}

fn 成分の値(成分: &[blitz_math::逆メートル; 3]) -> [f32; 3] {
    [成分[0].値(), 成分[1].値(), 成分[2].値()]
}

#[test]
fn 惑星の2つの半径が方針のまま運ばれる() {
    let 媒体 = 地球標準の媒体();
    assert_eq!(媒体.消散().下端半径().値(), 6_360_000.0);
    assert_eq!(媒体.消散().上端半径().値(), 6_460_000.0);
}

#[test]
fn 三成分の消散係数が方針のまま運ばれる() {
    let 媒体 = 地球標準の媒体();
    let 消散 = 媒体.消散();
    assert_eq!(成分の値(&消散.レイリー().消散係数().成分()), [5.802e-6, 13.558e-6, 33.100e-6]);
    // ミーの消散は方針が散乱3.996e-6と吸収0.444e-6の和として導く。3つを別々に運ぶとこの関係が破れうる。
    assert_eq!(成分の値(&消散.ミー().消散係数().成分()), [4.440e-6; 3]);
    assert_eq!(成分の値(&消散.吸収().消散係数().成分()), [0.650e-6, 1.881e-6, 0.085e-6]);
}

#[test]
fn 散乱係数と位相の偏りと地表の反射率が方針のまま運ばれる() {
    let 媒体 = 地球標準の媒体();
    assert_eq!(成分の値(&媒体.レイリー散乱係数().成分()), [5.802e-6, 13.558e-6, 33.100e-6]);
    assert_eq!(成分の値(&媒体.ミー散乱係数().成分()), [3.996e-6; 3]);
    assert_eq!(媒体.位相非対称係数().値(), 0.8);
    assert_eq!(媒体.地表アルベド().成分(), [0.1; 3]);
}

/// 尺度高度から組み直すのでなく層の係数を写すことを、指数分布の減衰率で確かめる。
#[test]
fn 指数分布の減衰率が尺度高度の逆数の符号を反転した値になる() {
    let 媒体 = 地球標準の媒体();
    let レイリー本体 = 媒体.消散().レイリー().密度分布().層()[1];
    assert_eq!(レイリー本体.指数項(), 1.0);
    assert_eq!(レイリー本体.指数尺度().値(), -1.0 / 8000.0);
    let ミー本体 = 媒体.消散().ミー().密度分布().層()[1];
    assert_eq!(ミー本体.指数尺度().値(), -1.0 / 1200.0);
}

/// オゾンの折れ線は指数でなく線形項と定数項で表される。上りの担当区間の上限が頂点高度25kmであることを固定する。
#[test]
fn 吸収層の折れ線が上りと下りの2層として運ばれる() {
    let 媒体 = 地球標準の媒体();
    let [上り, 下り] = 媒体.消散().吸収().密度分布().層();
    assert_eq!(上り.幅().値(), 25_000.0);
    assert_eq!(上り.線形項().値(), 1.0 / 15_000.0);
    assert_eq!(上り.定数項(), -10_000.0 / 15_000.0);
    assert_eq!(下り.線形項().値(), -1.0 / 15_000.0);
    assert_eq!(下り.定数項(), 40_000.0 / 15_000.0);
}
