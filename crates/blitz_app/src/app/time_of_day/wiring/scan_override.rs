//! 段差の走査を持ち、1撮影ごとの条件を据える局面。触れるフィールドは段差走査・時間帯・間引き・ライティングの
//! 4つだけであり、焼き直しの判定にも露出方式にも触れない。
//!
//! 走査を天空配線が持つのは、撮影が据えるのが時刻と太陽天頂区間の2つであり、どちらもこの型が所有する状態だからである。
//! 呼ばれるのはフレームの世界更新で時計を進めた直後であり、描画入力を組む前である。時計を進めた後に据えるのは、
//! 据えた時刻を同じフレームの進行が上書きしないためである。
//!
//! 時刻の据え直しがライティングを導き直すのは、時刻が方向光の向き・色・強度と環境光を決めるためである。
//! 導き直さないと、絵の直接光だけが起動時の時刻のまま取り残される。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」

use blitz_engine::time::世界時刻;
use blitz_math::大域秒;

use super::super::step_scan::{撮影指定, 段差走査};
use super::天空配線;
use crate::cli::{起動モード, 起動引数エラー};

impl 天空配線 {
    /// 起動指定が段差の走査を選んでいれば組み立てる。空を持たない世界には太陽の軌道が無く、区間の境界も無い。
    pub(in crate::app) fn 段差走査を組む(&mut self, モード: 起動モード) -> Result<(), 起動引数エラー> {
        let 起動モード::段差走査実行 { 走査指定 } = モード else {
            return Ok(());
        };
        let 方針 = self
            .時間帯
            .as_ref()
            .map(super::super::clock::時間帯::方針)
            .ok_or_else(|| 起動引数エラー::段差走査範囲不正("空を持たない世界には太陽天頂区間の境界が無い".to_string()))?;
        self.段差走査 = Some(段差走査::組む(走査指定, &方針, self.間引き.刻み())?);
        Ok(())
    }

    /// そのフレームで撮っている撮影。段差の走査でない実行では無い。
    pub(in crate::app) fn このフレームの撮影(&self, 現在フレーム: u32) -> Option<撮影指定> {
        self.段差走査.as_ref()?.このフレームの撮影(現在フレーム)
    }

    /// そのフレームで圧縮前のHDRを読み戻すか。段差の走査でない実行では常に偽である。
    pub(in crate::app) fn 段差走査で読み戻すフレームか(&self, 現在フレーム: u32) -> bool {
        self.段差走査.as_ref().is_some_and(|走査| 走査.このフレームで読み戻すか(現在フレーム))
    }

    /// そのフレームの撮影の条件を据える。時刻は一日の始まりからの秒であり、紀元が一日の始まりであるため
    /// そのまま世界時刻になる。区間の上書きは遠方環境の焼く入力だけを動かし、空背景と直接光は時刻のまま残る。
    pub(in crate::app) fn 撮影の条件を据える(&mut self, 現在フレーム: u32) {
        let Some(撮影) = self.このフレームの撮影(現在フレーム) else {
            return;
        };
        let 時刻 = 世界時刻::生成する(大域秒::生成する(撮影.一日内秒))
            .unwrap_or_else(|誤り| panic!("段差の走査が据える一日内秒から世界時刻を作れなかった: {誤り}"));
        if let Some(時間帯) = &mut self.時間帯 {
            時間帯.時刻を据える(時刻);
        }
        self.間引き.上書きを据える(撮影.区間の上書き());
        self.ライティングを導き直す();
    }
}
