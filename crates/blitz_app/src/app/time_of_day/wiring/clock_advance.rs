//! 時計を進めて、そのフレームのライティングを基準から導き直す局面。
//!
//! いつ呼ばれるか: 毎フレーム1回である。起動時に1回だけ呼ばれる`band_decision`とは呼び出しの頻度が違う。
//!
//! 触れるフィールドは時間帯・基準ライティング・ライティングの3つに限る。ライティングは基準から毎回導き直す
//! 派生値であり、前のフレームの結果を足し込まない。時刻の無い世界では基準がそのままそのフレームの値になる。

use super::天空配線;

impl 天空配線 {
    /// 実時間の経過ぶん時計を進め、時刻が動いたぶんだけライティングと空入力を導き直す。
    pub(in crate::app) fn 進める(&mut self) {
        let Some(時間帯) = &mut self.時間帯 else {
            return;
        };
        時間帯.進める();
        self.ライティングを導き直す();
    }

    pub(super) fn ライティングを導き直す(&mut self) {
        let Some(時間帯) = &self.時間帯 else {
            self.ライティング = self.基準ライティング;
            return;
        };
        self.ライティング = blitz_engine::天空状態をライティングへ写す(self.基準ライティング, 時間帯.状態())
            .unwrap_or_else(|誤り| panic!("天空状態からライティング入力を作れなかった: {誤り}"));
    }
}
