//! 天空配線のうち、そのフレームで何を焼き直すかを決める操作。触れるフィールドは時間帯・下ろし済みの大気・
//! 間接照明方針・2つの更新判定・間引きだけであり、ライティングと露出へは触れない。
//! 判定と間引きが数えた記録の読み取りも、同じフィールドだけを触るためここが持つ。
//!
//! 大気と遠方環境を1つの呼び出しで返すのは、どちらも同じフレームの天空状態と空描画方針から決まり、
//! 別々に導くと違う時刻の状態から2つの入力が作られうるためである。
//!
//! 呼び出し規律: 2つの更新判定は保留中の鍵を書き換えるため、1フレームに1度だけ呼ぶ。判定は前回焼いた鍵を
//! 書き換えず、そのフレームが提示へ到達したときに`焼き上げを確定する`が保留を格上げする。

use blitz_render::atmosphere_lut_input::大気のベイク済み画像の入力;
use blitz_render::distant_environment::遠方環境の入力;

use super::super::{atmosphere_input, distant_environment_input};
use super::天空配線;
use crate::app::frame::フレーム視点;

/// そのフレームの焼き上げ入力の組。どちらも、その資源を作らない構成・契約では`None`である。
pub(in crate::app) struct 焼き上げ入力の組 {
    pub(in crate::app) 大気: Option<大気のベイク済み画像の入力>,
    pub(in crate::app) 遠方環境: Option<遠方環境の入力>,
}

impl 天空配線 {
    /// 遠方環境を焼くフレームか。契約が遠方環境の枝なら、空を描かない起動指定でも焼く
    /// (空背景の有無と表面への間接照明は独立である)。
    fn 遠方環境を焼くか(&self) -> bool {
        self.照明問い合わせ契約.遠方環境の資源を作るか()
    }

    /// 大気のベイク済み画像を焼くフレームか。判定を契約へ委ねるのは、レンダラーの資源生成が同じ判定を使うためである。
    /// 条件をここで書き直すと、資源の有無とフレーム入力の有無が食い違って描画が型付きエラーで落ちる。
    fn 大気を焼くか(&self) -> bool {
        self.照明問い合わせ契約.大気のベイク済み画像を作るか(self.空を描く)
    }

    /// 遠方環境の焼き直し判定が何を見て何を答えたかの記録。定数近似の契約では1フレームも判定しないため空のままである。
    pub(in crate::app) fn 遠方環境の鍵の記録(&self) -> &crate::app::遠方環境の鍵の記録 {
        self.遠方環境更新判定.記録()
    }

    /// そのフレームの太陽天頂区間の記録。定数近似の契約では1フレームも判定しないため空のままである。
    pub(in crate::app) fn 太陽天頂区間の記録(&self) -> &crate::app::太陽天頂区間の記録 {
        self.間引き.記録()
    }

    /// 直前に組んだ焼き上げ入力のフレームが提示へ到達したときに呼ぶ。2つの判定の保留中の鍵を確定する。
    /// 到達しなかったフレームで呼ばないことが、焼いていない鍵を焼いたことにしない唯一の担保である。
    pub(in crate::app) fn 焼き上げを確定する(&mut self) {
        self.大気更新判定.確定する();
        self.遠方環境更新判定.確定する();
    }

    /// ベイク済み画像生成の入力になる大気と2つの観測条件、遠方環境の明るさの尺度、そのフレームで何を焼き直すかの指示。
    /// 空中遠近の条件はカメラに依るため視点を受け取る。大気のベイク済み画像資源は「空段階がある、または契約が
    /// 遠方環境の枝である」ときに作られるため、空パスを積まない指定(`--no-sky`)でも遠方環境の契約なら媒体を渡す。
    pub(in crate::app) fn 焼き上げ入力(&mut self, 視点: &フレーム視点) -> 焼き上げ入力の組 {
        let 無し = 焼き上げ入力の組 {
            大気: None, 遠方環境: None
        };
        let Some((方針, 媒体)) = self.大気を焼くか().then_some(self.大気).flatten() else {
            return 無し;
        };
        let Some(時間帯) = self.時間帯.as_ref() else {
            return 無し;
        };
        let 空描画 = 時間帯.空描画方針();
        let 状態 = *時間帯.状態();
        let 材料 = atmosphere_input::大気入力の材料 {
            方針: &方針,
            媒体,
            状態: &状態,
            空描画,
            視点,
        };
        let 大気入力 = atmosphere_input::組む(&材料, &mut self.大気更新判定);
        let 遠方環境の材料 = distant_environment_input::遠方環境入力の材料 {
            大気の静的キー: 方針.静的キー(),
            空描画,
            状態: &状態,
        };
        焼き上げ入力の組 {
            大気: Some(大気入力),
            遠方環境: self
                .遠方環境を焼くか()
                .then(|| distant_environment_input::組む(&遠方環境の材料, &mut self.遠方環境更新判定, &mut self.間引き)),
        }
    }
}
