//! カタログを読んで世界級の遠景の有無が確定した後に、影の距離区分の分け方を決める局面。
//!
//! いつ呼ばれるか: ウィンドウとレンダラーを組み上げた直後の起動時1回だけである。毎フレーム走る`進める`とは
//! 呼び出しの頻度も触れるフィールドも違うため、同じ型の操作でもここに分けて置く。
//!
//! 起動設定だけを見る`cascade_policy`でこれを決められないのは、どちらの分け方になるかがカタログの中身
//! (世界級の遠景地形があるか)で決まり、カタログを読むのが基準ライティングを組み立てた後だからである。
//! シーン名では決められない。同じ`terrain_fox_tour`が、3×3のクソゲー世界と8km×10kmの大規模世界の両方で
//! 使われており、2つを分けているのはアセットルートの中身だけである。
//!
//! 触れるフィールドは基準ライティングとライティングの2つに限る。分け方を替えたら、そのフレームのライティングを
//! 基準から導き直さなければ、最初のフレームだけ古い分け方の多段が組まれる。

use super::天空配線;
use crate::app::scene_lighting::大規模世界の距離区分の割り当てを作る;

impl 天空配線 {
    pub(in crate::app) fn 距離区分の分け方を確定する(&mut self, 世界級の遠景がある: bool) {
        if 世界級の遠景がある && !self.明示境界を使わない {
            let 多段設定 = self
                .基準ライティング
                .多段設定()
                .割り当てを差し替える(大規模世界の距離区分の割り当てを作る());
            self.基準ライティング = self.基準ライティング.多段設定を差し替える(多段設定);
            self.ライティングを導き直す();
        }
        crate::reports::shadow_band_assignment::影の距離区分の分け方を表示する(
            self.基準ライティング.多段設定().割り当て(),
            世界級の遠景がある,
            self.明示境界を使わない,
        );
    }
}
