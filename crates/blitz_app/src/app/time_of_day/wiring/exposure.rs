//! 露出の合成。担当するのは「世界が宣言した露出方式を答え、そのフレームの露出倍率を作り、自動露出の資源に要る設定を組む」ことである。
//! 触れるのは`露出方式`と`時間帯`の2つだけであり、間接照明も焼き直しの判定も読まない。
//!
//! CPU正本の既定値を開いてGPU境界の設定へ写すのをコンポジションルートが持つのは、境界の線形輝度の列を
//! CPU正本からGPUへ運ぶ経路が1本だけであるべきだからである。定数をレンダラー側にもう1つ置くと、
//! CPUとGPUでビンが1つもずれない契約が二重台帳の上に立つ。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「順3-IIの実装設計」

use blitz_engine::auto_exposure::{境界の線形輝度, 目標中間灰, 自動補正段の上下限, 露出の適応速度, 露出方式};

use super::天空配線;

/// 自動露出が1フレームで進む秒数。実時間でなく固定の刻みにするのは、同じ入力列から同じ適応系列が出ることを
/// 検収で確かめるためである(判断47のアニメーション時刻と同じ理由であり、値も同じ毎秒60フレーム相当である)。
const 一フレームの経過秒: f32 = 1.0 / 60.0;

impl 天空配線 {
    /// 明るさの圧縮へ渡す露出倍率。時刻別固定の枝では基準の露出倍率へ天空状態の露出補正段を2の冪として掛ける。
    ///
    /// ヒストグラム自動の枝で時刻の補正を掛けないのは、同じ明るさを時刻と自動の2つの系統が別々に動かさないためである。
    /// 自動の枝ではGPUが芸術的バイアスと自動補正段を掛けるため、ここが渡すのは基準の倍率そのものである。
    pub(in crate::app) fn 露出倍率(&self, 基準露出: f32) -> f32 {
        let Some(時間帯) = &self.時間帯 else {
            return 基準露出;
        };
        if matches!(self.露出方式, 露出方式::ヒストグラム自動 { .. }) {
            return 基準露出;
        }
        基準露出 * 2.0_f32.powf(時間帯.状態().露出補正段().値())
    }

    /// レンダラーの生成へ渡す自動露出の設定。値そのものは1つも決めず、CPU正本の既定値を開いて写すだけである。
    pub(in crate::app) fn 自動露出の設定(&self) -> blitz_render::auto_exposure::自動露出の設定 {
        let 上下限 = 自動補正段の上下限::既定値();
        let 速度 = 露出の適応速度::既定値();
        blitz_render::auto_exposure::自動露出の設定 {
            境界の線形輝度,
            目標中間灰の対数輝度: 目標中間灰::既定値().対数輝度で表す().値(),
            補正段の下限: 上下限.下限().値(),
            補正段の上限: 上下限.上限().値(),
            補正段を下げる速さ: 速度.補正段を下げる速さ().値(),
            補正段を上げる速さ: 速度.補正段を上げる速さ().値(),
            一フレームの経過秒,
            方式: 描画側の方式へ写す(self.露出方式),
        }
    }
}

fn 描画側の方式へ写す(方式: 露出方式) -> blitz_render::auto_exposure::露出方式 {
    match 方式 {
        露出方式::時刻別固定 => blitz_render::auto_exposure::露出方式::時刻別固定,
        露出方式::ヒストグラム自動 { 芸術的バイアス } => blitz_render::auto_exposure::露出方式::ヒストグラム自動 {
            芸術的バイアスの補正段: 芸術的バイアス.値(),
        },
    }
}
