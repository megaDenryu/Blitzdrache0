//! 視錐台の向きと最遠距離が、逆向き深度の規約どおりに射影の逆をたどっていることの反証。
//!
//! 深度の端点を正の向きの規約(遠平面が深度1)で組むと、最遠距離が近クリップの0.1メートルになり、
//! 中央の向きがカメラの真後ろを指す。この2つをそれぞれ落とすのが、ここの2つの検査である。
//! 前提: 既定のカメラは注視点の+Z側3メートルから原点を見るため、ビュー空間の前方はZの負の向きである。

#![allow(clippy::unwrap_used)]

use blitz_engine::カメラ;
use blitz_math::{クリップ, メートル, ワールド, 位置, 変換};

use super::aerial_frustum::視錐台の向きと最遠距離;

/// 検査で使うアスペクト比。横長の窓を表す値であり、最遠距離が画面中央で測られる限り結果は比に依らない。
const アスペクト比: f32 = 16.0 / 9.0;
/// 最遠距離の許容差。逆行列と透視除算を単精度で往復するぶんの誤差であり、遠クリップの1万分の1である。
const 最遠距離の許容差メートル: f32 = 1.0;

#[test]
fn 最遠距離はカメラの遠クリップに一致する() {
    let カメラ = カメラ::生成する();
    let 視錐台 = 導く(&カメラ);
    let 差 = (視錐台.最遠距離.値() - カメラ.遠クリップ().値()).abs();
    assert!(
        差 <= 最遠距離の許容差メートル,
        "最遠距離{}が遠クリップ{}と一致しない(逆向き深度では遠平面が深度0である)",
        視錐台.最遠距離.値(),
        カメラ.遠クリップ().値()
    );
}

#[test]
fn 視錐台の中央の向きはカメラの前を向く() {
    let カメラ = カメラ::生成する();
    let 視錐台 = 導く(&カメラ);
    let 中央の向き = [0, 1, 2].map(|軸| 視錐台.基準[軸] + 視錐台.横の差分[軸] * 0.5 + 視錐台.縦の差分[軸] * 0.5);
    let ビュー空間の向き = カメラ.カメラ相対ビュー変換を作る().適用する(ワールドの向きへ写す(中央の向き));
    assert!(
        ビュー空間の向き.z().値() < 0.0,
        "視錐台の中央の向きのビュー空間のZが{}であり前を向いていない(逆向き深度では近平面が深度1である)",
        ビュー空間の向き.z().値()
    );
}

fn 導く(カメラ: &カメラ) -> 視錐台の向きと最遠距離 {
    let 逆変換: 変換<クリップ, ワールド> = カメラ.カメラ相対ビュー射影変換を作る(アスペクト比).逆変換する();
    視錐台の向きと最遠距離::カメラ相対ビュー射影の逆から導く(&逆変換)
}

/// 向きの3成分をワールドの位置として包む。カメラ相対ビュー変換は平行移動を持たない回転だけの変換であるため、
/// 位置として写しても向きの写像と同じ結果になる(参照: `blitz_engine`の`カメラ相対ビュー変換を作る`)。
fn ワールドの向きへ写す(向き: [f32; 3]) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(向き[0]), メートル::生成する(向き[1]), メートル::生成する(向き[2]))
}
