//! 判定と確定の2段が、提示へ到達しなかったフレームで鍵を進めないことの検査。大気と遠方環境の2つの判定を
//! 同じ検査が見るのは、どちらも同じ地雷を持ち、片方だけ直しても絵の欠陥が残るためである。
//!
//! 落とす欠陥は次の並びである。鍵Aのフレームが焼いて提示へ到達する。鍵Bのフレームが判定だけされて
//! レンダラー未生成・最小化中・スワップチェーン再構築中のいずれかで見送られる。次に鍵Bで描くフレームが
//! 「前の結果を使う」と答えると、GPUの画像は鍵Aのまま恒久的に古い。

#![allow(clippy::unwrap_used)]

use blitz_engine::sky::atmosphere::大気媒体方針;
use blitz_engine::sky::{スカイビューキー, 太陽方向, 放射輝度色, 空中遠近キー, 遠方環境キー};
use blitz_math::メートル;
use blitz_render::atmosphere_lut_input::大気のベイク済み画像の生成指示;
use blitz_render::distant_environment::input::遠方環境の生成指示;

use super::atmosphere_update::大気更新判定;
use super::distant_environment_update::遠方環境更新判定;

const 観測高度: f32 = 1.5;

fn スカイビュー鍵(太陽天頂余弦: f32) -> スカイビューキー {
    スカイビューキー::導く(大気媒体方針::地球標準().静的キー(), 太陽天頂余弦, メートル::生成する(観測高度))
}

fn 遠方環境の鍵(太陽天頂余弦: f32) -> 遠方環境キー {
    遠方環境キー::導く(スカイビュー鍵(太陽天頂余弦), 20.0, 放射輝度色::生成する(0.002, 0.002, 0.005).unwrap())
}

fn 空中遠近の鍵(太陽天頂余弦: f32) -> 空中遠近キー {
    let 太陽 = 太陽方向::生成する(0.0, 1.0, 0.0).unwrap();
    空中遠近キー::導く(
        スカイビュー鍵(太陽天頂余弦),
        太陽,
        [0.0, 0.0, -1.0],
        [1.6, 0.0, 0.0],
        [0.0, -0.9, 0.0],
        メートル::生成する(2000.0),
    )
}

#[test]
fn 遠方環境は見送ったフレームの鍵を確定しない() {
    let mut 判定 = 遠方環境更新判定::新規();
    assert_eq!(判定.判定する(遠方環境の鍵(0.5)), 遠方環境の生成指示::焼き直す);
    判定.確定する();
    // 鍵を変えたフレームを判定だけして見送る(確定を呼ばない)。
    assert_eq!(判定.判定する(遠方環境の鍵(0.6)), 遠方環境の生成指示::焼き直す);
    assert_eq!(
        判定.判定する(遠方環境の鍵(0.6)),
        遠方環境の生成指示::焼き直す,
        "見送ったフレームの鍵を確定したため次のフレームが焼き直さなかった"
    );
}

#[test]
fn 大気は見送ったフレームの鍵を確定しない() {
    let mut 判定 = 大気更新判定::新規();
    assert_eq!(判定.判定する(空中遠近の鍵(0.5)), 大気のベイク済み画像の生成指示::全部焼き直す);
    判定.確定する();
    // 鍵を変えたフレームを判定だけして見送る(確定を呼ばない)。
    assert_eq!(
        判定.判定する(空中遠近の鍵(0.6)),
        大気のベイク済み画像の生成指示::スカイビューと空中遠近を焼き直す
    );
    assert_eq!(
        判定.判定する(空中遠近の鍵(0.6)),
        大気のベイク済み画像の生成指示::スカイビューと空中遠近を焼き直す,
        "見送ったフレームの鍵を確定したため次のフレームが焼き直さなかった"
    );
}

#[test]
fn 焼かないと答えたフレームの確定は鍵を動かさない() {
    let mut 判定 = 遠方環境更新判定::新規();
    assert_eq!(判定.判定する(遠方環境の鍵(0.5)), 遠方環境の生成指示::焼き直す);
    判定.確定する();
    assert_eq!(判定.判定する(遠方環境の鍵(0.5)), 遠方環境の生成指示::前の結果を使う);
    判定.確定する();
    assert_eq!(
        判定.判定する(遠方環境の鍵(0.6)),
        遠方環境の生成指示::焼き直す,
        "鍵が変わったのに焼かなかった"
    );
}
