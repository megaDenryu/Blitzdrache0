//! 太陽天頂区間の記録が、生成パスがGPUへ届いたフレームだけを数えることの検査。
//!
//! 2つの更新判定の確定を見る`bake_commit_tests`と別のファイルへ置くのは、確かめる対象が違うためである。
//! あちらは「見送ったフレームの鍵を焼いたことにしない」という絵の欠陥を落とし、ここは「見送ったフレームを
//! 数えたせいで検収の整数が合わなくなる」という計器の欠陥を落とす。
//!
//! 落とす欠陥は、区間の記録が描画呼び出しの前にただちに数える形である。この形では、レンダラー未生成・
//! 最小化中・スワップチェーン再構築中で生成パスがGPUへ1本も届かなかったフレームが区間の変化回数を増やす一方、
//! 間接照明生成パス数の焼き直したフレーム数は増えない。検収の厳密一致
//! (焼き直したフレーム数=区間が変わった回数+初回の1回)が実行条件次第で成り立たなくなる。

#![allow(clippy::unwrap_used)]

use super::thinning::遠方環境の間引き;

/// 刻みの初期値(値域[-1, +1]を200区間)で別々の区間へ入る2つの天頂余弦。境界の値を避けて区間の内側に取る。
const 区間Aの天頂余弦: f32 = 0.505;
const 区間Bの天頂余弦: f32 = 0.605;

#[test]
fn 見送ったフレームで変わった区間は次の到達で1度だけ数える() {
    let mut 間引き = 遠方環境の間引き::新規();
    間引き.区間を決める(区間Aの天頂余弦);
    間引き.確定する();
    // 区間Bのフレームを決めるだけで見送る(確定を呼ばない)。
    間引き.区間を決める(区間Bの天頂余弦);
    間引き.区間を決める(区間Bの天頂余弦);
    間引き.確定する();
    let 記録 = 間引き.記録();
    assert_eq!(記録.区間が変わった回数(), 1, "GPUへ届いた更新の回数と区間の変化回数が食い違う");
    assert_eq!(記録.提示へ到達したフレーム数(), 2, "GPUへ届かなかったフレームを数えた");
}

#[test]
fn 見送ったフレームだけで変わった区間は変化に数えない() {
    let mut 間引き = 遠方環境の間引き::新規();
    間引き.区間を決める(区間Aの天頂余弦);
    間引き.確定する();
    // 区間Bへ移ったフレームを見送り、区間Aへ戻ったフレームが提示へ到達する。
    間引き.区間を決める(区間Bの天頂余弦);
    間引き.区間を決める(区間Aの天頂余弦);
    間引き.確定する();
    let 記録 = 間引き.記録();
    assert_eq!(記録.区間が変わった回数(), 0, "GPUへ届いた区間が変わっていないのに変化に数えた");
    assert_eq!(記録.提示へ到達したフレーム数(), 2, "GPUへ届かなかったフレームを数えた");
}
