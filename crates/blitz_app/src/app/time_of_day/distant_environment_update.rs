//! 遠方環境を焼き直すかどうかを決める工程。担当するのは「遠方環境キーを前回焼いた値と比べ、2つの指示のどちらかを
//! 返す」ことである。触れる状態は前回の鍵と保留中の鍵であり、判定の結果を変えない計器を`記録`が別に持つ。
//!
//! 大気の更新判定と別の型にするのは、比べる鍵が違うためである。遠方環境キーは太陽放射照度と夜空放射輝度も見るため、
//! 空描画方針の明るさだけを変えたフレームでは大気を焼き直さずに遠方環境だけを焼き直す。
//!
//! 可変なdirty通知でなく鍵の値の比較で決めるのは、通知の付け忘れが「方針を変えたのに古い遠方環境を参照し続ける」
//! という絵にしか現れない欠陥になるためである。履歴・乱数・フレーム番号・時間積算を判定へ入れない
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「検収(機械判定)」)。
//!
//! 判定と確定を2段に分けるのは、判定したフレームが提示へ到達しない経路があるためである。レンダラー未生成・
//! 最小化中・スワップチェーン再構築中のフレームは生成パスがGPUへ1本も届かない。判定の時点で前回の鍵を
//! 書き換えると、その鍵で焼いたことにされて次の実描画が「前の結果を使う」と答え、GPUの画像は古いまま恒久的に残る。

use blitz_engine::sky::遠方環境キー;
use blitz_render::distant_environment::input::遠方環境の生成指示;

use super::distant_environment_key_record::遠方環境の鍵の記録;

pub(crate) struct 遠方環境更新判定 {
    /// 直近に焼き、そのフレームが提示へ到達したときの鍵。まだ1度も焼いていないフレームでは`None`であり、最初のフレームが必ず焼く。
    前回焼いた鍵: Option<遠方環境キー>,
    /// 焼くと判定したが、そのフレームが提示へ到達したことをまだ確かめていない鍵。
    保留中の鍵: Option<遠方環境キー>,
    /// 何を見て何を答えたかの記録。判定の結果を1つも変えない計器であり、検収だけが読む。
    記録: 遠方環境の鍵の記録,
}

impl 遠方環境更新判定 {
    pub(crate) fn 新規() -> Self {
        Self {
            前回焼いた鍵: None,
            保留中の鍵: None,
            記録: 遠方環境の鍵の記録::新規(),
        }
    }

    pub(crate) fn 記録(&self) -> &遠方環境の鍵の記録 {
        &self.記録
    }

    /// そのフレームの鍵を受け取り、焼き直すかどうかを返す。焼くと答えた鍵は保留に置くだけであり、
    /// 前回焼いた鍵は`確定する`まで書き換えない。
    pub(crate) fn 判定する(&mut self, 鍵: 遠方環境キー) -> 遠方環境の生成指示 {
        let 指示 = self.鍵を比べる(鍵);
        self.記録.記録する(鍵, 指示);
        指示
    }

    fn 鍵を比べる(&mut self, 鍵: 遠方環境キー) -> 遠方環境の生成指示 {
        if self.前回焼いた鍵 == Some(鍵) {
            self.保留中の鍵 = None;
            return 遠方環境の生成指示::前の結果を使う;
        }
        self.保留中の鍵 = Some(鍵);
        遠方環境の生成指示::焼き直す
    }

    /// 直前に判定したフレームが提示へ到達したときに呼ぶ。保留中の鍵を前回焼いた鍵へ格上げする。
    pub(crate) fn 確定する(&mut self) {
        if let Some(鍵) = self.保留中の鍵.take() {
            self.前回焼いた鍵 = Some(鍵);
        }
    }
}
