//! 遠方環境を焼き直すかどうかを決める工程。担当するのは「遠方環境キーを前回焼いた値と比べ、2つの指示のどちらかを
//! 返す」ことである。触れる状態は前回の鍵1つだけである。
//!
//! 大気の更新判定と別の型にするのは、比べる鍵が違うためである。遠方環境キーは太陽放射照度と夜空放射輝度も見るため、
//! 空描画方針の明るさだけを変えたフレームでは大気を焼き直さずに遠方環境だけを焼き直す。
//!
//! 可変なdirty通知でなく鍵の値の比較で決めるのは、通知の付け忘れが「方針を変えたのに古い遠方環境を参照し続ける」
//! という絵にしか現れない欠陥になるためである。履歴・乱数・フレーム番号・時間積算を判定へ入れない
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「検収(機械判定)」)。

use blitz_engine::sky::遠方環境キー;
use blitz_render::distant_environment::input::遠方環境の生成指示;

pub(crate) struct 遠方環境更新判定 {
    /// 直近に焼いたときの鍵。まだ1度も焼いていないフレームでは`None`であり、最初のフレームが必ず焼く。
    前回焼いた鍵: Option<遠方環境キー>,
}

impl 遠方環境更新判定 {
    pub(crate) fn 新規() -> Self {
        Self { 前回焼いた鍵: None }
    }

    /// そのフレームの鍵を受け取り、焼き直すかどうかを返す。焼き直すと答えたときは鍵を記録する。
    pub(crate) fn 判定する(&mut self, 鍵: 遠方環境キー) -> 遠方環境の生成指示 {
        if self.前回焼いた鍵 == Some(鍵) {
            return 遠方環境の生成指示::前の結果を使う;
        }
        self.前回焼いた鍵 = Some(鍵);
        遠方環境の生成指示::焼き直す
    }
}
