//! シーンごとの世界の方針。担当するのは「世界の種別と起動指定から、その世界が空を持つかと、間接照明をどの供給元が答えるかを決める」ことである。
//!
//! 検証世界(平面板・ヘルメット・影の検収世界・キツネ・植生の各世界)は空を持たない。空は深度がクリア値のままの画素を塗り替えるため、
//! 背景がクリア色であることを前提にした既存の画素判定が空を積むと成立しなくなる。地形世界だけが空を持ち、
//! 空・方向光・環境光・露出を時刻から導く。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「段階導入」
//! そのフレームへ空パスを積むかどうかの判定は`sky_pass_choice`が持ち、世界の種別からの分類は`world_class`が持つ。

mod sky_pass_choice;
mod world_class;

use blitz_engine::auto_exposure::露出方式;
use blitz_engine::local_visibility::拡散間接方式;
use blitz_engine::sky::{世界の空方針, 世界の間接照明方針};
use blitz_engine::temporal_reconstruction::時間再構成方式;
pub(in crate::app) use sky_pass_choice::空パスを積むか as 空を描くか;

use crate::cli::local_visibility_settings::{局所可視性の起動指定, 拡散間接方式の起動上書き};
use crate::cli::temporal_reconstruction_settings::時間再構成方式の起動上書き;
use crate::cli::{世界の種別, 空の起動指定, 自動露出の起動指定};
use world_class::{地形チャンクを敷く世界か, 大気の媒体を持つ世界か, 履歴混合を受ける地形世界か};

/// この世界が空を持つのは、天空の遠方環境が大気の媒体を要るためである。媒体を持たない世界がこの方針を選ぶと
/// 契約の構築が型付きの失敗になる。空パスを積むかどうかは別であり、`--no-sky`で背景だけを外せる。
pub(in crate::app) fn 世界の空方針を決める(種別: 世界の種別, 指定: 空の起動指定) -> 世界の空方針 {
    if 指定 == 空の起動指定::空ありとして扱う || 大気の媒体を持つ世界か(種別) {
        return 世界の空方針::空ありの既定();
    }
    世界の空方針::空なし
}

/// 世界の間接照明方針。天空の遠方環境を選ぶのは地形の本番世界と間接照明の検収世界であり、残りの全世界は
/// 定数近似のままである(参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Ic-3bの実装」)。
///
/// 空方針と別に決めるのは、空背景の有無と表面への間接照明が独立だからである。空の起動指定を受け取らないのも
/// 同じ理由であり、`--no-sky`は背景だけを止めて間接照明の方針を動かさない。空方針と同じ分類を使うのは、
/// 地形チャンクを敷く世界がすべて大気の媒体を持ち、遠方環境の契約が成立するためである。
pub(in crate::app) fn 世界の間接照明方針を決める(種別: 世界の種別) -> 世界の間接照明方針 {
    if 大気の媒体を持つ世界か(種別) {
        return 世界の間接照明方針::天空の遠方環境;
    }
    世界の間接照明方針::定数近似
}

/// 世界の露出方式。地形チャンクを敷く世界(本番と目視見本)がヒストグラム自動を選び、残りの全世界は時刻別固定である。
/// `--no-auto-exposure`は宣言を時刻別固定へ落とす。照明そのものを見る検収が、露出で割られた最終色でなく
/// 時刻から導く明るさを測るためである。
///
/// 間接照明方針と別に決めるのは、照明の供給と画の完成が別の軸だからである。間接照明の検収世界を含めないのは、
/// その世界の判定が板の画素の値そのものを見ており、画面全体の明るさで露出が動くと期待値が立たなくなるためである。
/// 芸術的バイアスを0段に置くのは、まず目標中間灰と上下限だけで絵を見るためである(最終値はオーナーの絵の目視で裁定する)。
pub(in crate::app) fn 世界の露出方式を決める(種別: 世界の種別, 指定: 自動露出の起動指定) -> 露出方式 {
    if 指定 == 自動露出の起動指定::時刻別固定で描く || !地形チャンクを敷く世界か(種別) {
        return 露出方式::時刻別固定;
    }
    let 芸術的バイアス = blitz_engine::sky::露出補正段::生成する(0.0).unwrap_or_else(|誤り| panic!("芸術的バイアスの既定値が不正だった: {誤り}"));
    露出方式::ヒストグラム自動 { 芸術的バイアス }
}

/// 世界の拡散間接方式。地形チャンクを敷く世界(本番と目視見本)が局所可視性補正を選び、残りの全世界は環境のみである。
/// `--no-ssao`は宣言を環境のみへ落とす。
///
/// 間接照明方針・露出方式と別に決めるのは、3つが独立の軸だからである。局所可視性補正は拡散間接照度へ掛かる係数で
/// あって、照度そのものの供給元でも画の完成の段でもない。間接照明の検収世界を含めないのは、その世界の判定が板の
/// 画素の値そのものを見ており、近傍の形から来る陰りが乗ると期待値が立たなくなるためである。
pub(in crate::app) fn 世界の拡散間接方式を決める(種別: 世界の種別, 指定: 局所可視性の起動指定) -> 拡散間接方式 {
    if 指定.方式の上書き == 拡散間接方式の起動上書き::環境のみで描く || !地形チャンクを敷く世界か(種別) {
        return 拡散間接方式::環境のみ;
    }
    拡散間接方式::局所可視性補正付き環境
}

/// 世界の時間再構成方式。地形世界だけが履歴混合を選び、残りの全世界は使わないである。
/// `--no-taa`は宣言を使わないへ落とす。
///
/// 拡散間接方式と別に決めるのは、時間再構成が画の完成のあとに掛かる時間方向の平均化であって、表面の陰りでも
/// 照度の供給元でもないためである。地形世界の判定に既存3軸と同じ分類を使うのは、目視見本の世界が
/// 本番世界と同じ軸で描かれなければ、見本で見た絵が本番の絵の代わりにならないためである。
/// 間接照明の検収世界を含めないのは、その世界の判定が板の画素の値そのものを見ており、フレームをまたぐ混合が
/// 入ると期待値が立たなくなるためである(露出方式・拡散間接方式が同じ理由でこの世界を外している)。
/// 場所巡りの世界を外すのは、動く個体が前のフレームの変換を持たず、カメラの動きぶんしか動きベクトルを持たないためである。
/// 混ぜると歩くキツネが尾を引いた絵になる。動く個体が前のフレームの変換を持つようになった時点でこの除外を外す。
pub(in crate::app) fn 世界の時間再構成方式を決める(
    種別: 世界の種別, 指定: 時間再構成方式の起動上書き
) -> 時間再構成方式 {
    if 指定 == 時間再構成方式の起動上書き::使わないで描く || !履歴混合を受ける地形世界か(種別) {
        return 時間再構成方式::使わない;
    }
    時間再構成方式::履歴混合
}
