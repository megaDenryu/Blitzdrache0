//! シーンごとの世界の方針。担当するのは「シーン名と起動指定から、その世界が空を持つかと、間接照明をどの供給元が答えるかを決める」ことである。
//!
//! 検証世界(quad・helmet・shadow_scene・fox・植生の各世界)は空を持たない。空は深度がクリア値のままの画素を塗り替えるため、
//! 背景がクリア色であることを前提にした既存の画素判定が空を積むと成立しなくなる。地形世界だけが空を持ち、
//! 空・方向光・環境光・露出を時刻から導く。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「段階導入」

use blitz_engine::sky::{世界の空方針, 世界の間接照明方針};

use crate::cli::空の起動指定;

/// 空を持つ世界の名前の接頭辞。`terrain_origin`をはじめ、地形チャンクを敷く世界はすべてこの接頭辞で始まる。
const 地形世界の接頭辞: &str = "terrain";

pub(in crate::app) fn 世界の空方針を決める(シーン名: &str, 指定: 空の起動指定) -> 世界の空方針 {
    if 指定 == 空の起動指定::空ありとして扱う || シーン名.starts_with(地形世界の接頭辞) {
        return 世界の空方針::空ありの既定();
    }
    世界の空方針::空なし
}

/// 世界の間接照明方針。現時点ではシーン名を1つも見分けず、すべての世界が定数近似である。地形の本番世界を
/// 天空の遠方環境へ切り替えるのは順3-Ic-3である(参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」)。
/// それでもシーン名を受け取るのは、この関数の契約が「世界ごとに決める」ことであり、切り替えの入口をここへ固定するためである。
///
/// 空方針と別に決めるのは、空背景の有無と表面への間接照明が独立だからである。空の起動指定を受け取らないのも
/// 同じ理由であり、`--no-sky`は背景だけを止めて間接照明の方針を動かさない。
pub(in crate::app) fn 世界の間接照明方針を決める(_シーン名: &str) -> 世界の間接照明方針 {
    世界の間接照明方針::定数近似
}

/// 空パスを積むか。方針が空ありでも`--no-sky`は積まない。方針が空なしのとき、`--sky`は方針そのものを空ありへ上書き済みである。
pub(in crate::app) fn 空を描くか(方針: 世界の空方針, 指定: 空の起動指定) -> bool {
    match (方針, 指定) {
        (_, 空の起動指定::空を描かない) | (世界の空方針::空なし, _) => false,
        (世界の空方針::空あり { .. }, _) => true,
    }
}
