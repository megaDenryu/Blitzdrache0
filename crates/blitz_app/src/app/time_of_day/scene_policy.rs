//! シーンごとの世界の方針。担当するのは「シーン名と起動指定から、その世界が空を持つかと、間接照明をどの供給元が答えるかを決める」ことである。
//!
//! 検証世界(quad・helmet・shadow_scene・fox・植生の各世界)は空を持たない。空は深度がクリア値のままの画素を塗り替えるため、
//! 背景がクリア色であることを前提にした既存の画素判定が空を積むと成立しなくなる。地形世界だけが空を持ち、
//! 空・方向光・環境光・露出を時刻から導く。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「段階導入」

use blitz_engine::auto_exposure::露出方式;
use blitz_engine::local_visibility::拡散間接方式;
use blitz_engine::sky::{世界の空方針, 世界の間接照明方針};

use crate::cli::local_visibility_settings::{局所可視性の起動指定, 拡散間接方式の起動上書き};
use crate::cli::{空の起動指定, 自動露出の起動指定};

/// 空を持つ世界の名前の接頭辞。`terrain_origin`をはじめ、地形チャンクを敷く世界はすべてこの接頭辞で始まる。
const 地形世界の接頭辞: &str = "terrain";

/// 遠方環境の消費を機械判定する専用の検収世界。金属と誘電体の板を粗さの水準ごとに並べた世界である
/// (参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」のIc-2)。
const 間接照明の検収世界: &str = "indirect_probe";

/// この世界が空を持つのは、天空の遠方環境が大気の媒体を要るためである。媒体を持たない世界がこの方針を選ぶと
/// 契約の構築が型付きの失敗になる。空パスを積むかどうかは別であり、`--no-sky`で背景だけを外せる。
pub(in crate::app) fn 世界の空方針を決める(シーン名: &str, 指定: 空の起動指定) -> 世界の空方針 {
    if 指定 == 空の起動指定::空ありとして扱う || シーン名.starts_with(地形世界の接頭辞) || シーン名 == 間接照明の検収世界
    {
        return 世界の空方針::空ありの既定();
    }
    世界の空方針::空なし
}

/// 世界の間接照明方針。天空の遠方環境を選ぶのは地形の本番世界と間接照明の検収世界であり、残りの全世界は
/// 定数近似のままである(参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Ic-3bの実装」)。
///
/// 空方針と別に決めるのは、空背景の有無と表面への間接照明が独立だからである。空の起動指定を受け取らないのも
/// 同じ理由であり、`--no-sky`は背景だけを止めて間接照明の方針を動かさない。地形世界の判定に空方針と同じ
/// 接頭辞を使うのは、地形チャンクを敷く世界がすべて大気の媒体を持ち、遠方環境の契約が成立するためである。
pub(in crate::app) fn 世界の間接照明方針を決める(シーン名: &str) -> 世界の間接照明方針 {
    if シーン名.starts_with(地形世界の接頭辞) || シーン名 == 間接照明の検収世界 {
        return 世界の間接照明方針::天空の遠方環境;
    }
    世界の間接照明方針::定数近似
}

/// 世界の露出方式。地形の本番世界だけがヒストグラム自動を選び、残りの全世界は時刻別固定である。
/// `--no-auto-exposure`は宣言を時刻別固定へ落とす。照明そのものを見る検収が、露出で割られた最終色でなく
/// 時刻から導く明るさを測るためである。
///
/// 間接照明方針と別に決めるのは、照明の供給と画の完成が別の軸だからである。間接照明の検収世界を含めないのは、
/// その世界の判定が板の画素の値そのものを見ており、画面全体の明るさで露出が動くと期待値が立たなくなるためである。
/// 芸術的バイアスを0段に置くのは、まず目標中間灰と上下限だけで絵を見るためである(最終値はオーナーの絵の目視で裁定する)。
pub(in crate::app) fn 世界の露出方式を決める(シーン名: &str, 指定: 自動露出の起動指定) -> 露出方式 {
    if 指定 == 自動露出の起動指定::時刻別固定で描く || !シーン名.starts_with(地形世界の接頭辞) {
        return 露出方式::時刻別固定;
    }
    let 芸術的バイアス = blitz_engine::sky::露出補正段::生成する(0.0).unwrap_or_else(|誤り| panic!("芸術的バイアスの既定値が不正だった: {誤り}"));
    露出方式::ヒストグラム自動 { 芸術的バイアス }
}

/// 世界の拡散間接方式。地形の本番世界だけが局所可視性補正を選び、残りの全世界は環境のみである。
/// `--no-ssao`は宣言を環境のみへ落とす。
///
/// 間接照明方針・露出方式と別に決めるのは、3つが独立の軸だからである。局所可視性補正は拡散間接照度へ掛かる係数で
/// あって、照度そのものの供給元でも画の完成の段でもない。間接照明の検収世界を含めないのは、その世界の判定が板の
/// 画素の値そのものを見ており、近傍の形から来る陰りが乗ると期待値が立たなくなるためである。
pub(in crate::app) fn 世界の拡散間接方式を決める(シーン名: &str, 指定: 局所可視性の起動指定) -> 拡散間接方式 {
    if 指定.方式の上書き == 拡散間接方式の起動上書き::環境のみで描く || !シーン名.starts_with(地形世界の接頭辞)
    {
        return 拡散間接方式::環境のみ;
    }
    拡散間接方式::局所可視性補正付き環境
}

/// 空パスを積むか。方針が空ありでも`--no-sky`は積まない。方針が空なしのとき、`--sky`は方針そのものを空ありへ上書き済みである。
pub(in crate::app) fn 空を描くか(方針: 世界の空方針, 指定: 空の起動指定) -> bool {
    match (方針, 指定) {
        (_, 空の起動指定::空を描かない) | (世界の空方針::空なし, _) => false,
        (世界の空方針::空あり { .. }, _) => true,
    }
}
