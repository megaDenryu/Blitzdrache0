//! ホットリローダーの確認結果(シェーダー再コンパイル・アセット再読込)をレンダラーへ反映する。
//! 触れるフィールドは`ホットリローダー`・`レンダラー`・`描画対象の並べ方`・`大域ずらし量`・`ストリーミング`・`ゲーム配線`に限る。
//! 呼び出しタイミング: `frame`の`一フレーム実行する`の冒頭で、その回の入力確定より前に呼ぶ(差し替えを同じフレームの描画から効かせるため)。

use super::アプリ;
use crate::hot_reload::ホットリロード結果;

/// 契約別のシェーダー束でシーンのパイプライン表を交換できたときに1回だけ出す行。
const 差し替え成功の行: &str = "[hot-reload] 契約別のシェーダー束でシーンのパイプラインを差し替えた";

impl アプリ {
    pub(super) fn ホットリロードを確認する(&mut self) {
        let 結果 = self.ホットリローダー.確認する();
        // 再読込は成否によらずディスクを読む。読んだ事実をここで数える。
        if matches!(
            結果,
            ホットリロード結果::アセット再読込成功 { .. } | ホットリロード結果::アセット再読込失敗 { .. }
        ) {
            self.シーン読込計数.読み込んだ(self.現在フレーム);
        }
        let 並べ方 = self.描画対象の並べ方;
        let 大域ずらし量 = self.大域ずらし量;
        let ゲーム配線 = &self.ゲーム配線;
        let Some(レンダラー) = &mut self.レンダラー else {
            return;
        };
        match 結果 {
            ホットリロード結果::変化なし => {}
            ホットリロード結果::シェーダー再コンパイル成功 { シェーダー } => {
                match レンダラー.シェーダーを差し替える(シェーダー) {
                    // 注意: この行の綴りは`cargo xtask shader-reload-draw`が数える。差し替えが1度も起きなかった実行を
                    // 「絵が変わらなかった」だけで通さないための計数であり、文面を変えるときは検収側も同時に直す。
                    Ok(()) => println!("{}", 差し替え成功の行),
                    Err(誤り) => eprintln!("[hot-reload] パイプライン差し替えに失敗した: {誤り}"),
                }
            }
            ホットリロード結果::シェーダー再コンパイル失敗 { 誤り } => {
                eprintln!("[hot-reload] シェーダーの再コンパイルに失敗した:\n{誤り}");
            }
            ホットリロード結果::アセット再読込成功 { シーン } => {
                // シーン差し替えが成功したときだけ調停と束ごとの台帳をリセットする。失敗したときは従来の描画束がそのまま残っており、台帳と乖離しない。
                if let Some(登録一式) = アセット再読込を反映する(レンダラー, &シーン, 並べ方, 大域ずらし量, ゲーム配線)
                {
                    if let Err(誤り) =
                        self.永続束
                            .再登録する(レンダラー, &mut self.可視判定, &mut self.プリミティブ描画項目台帳, 登録一式, 大域ずらし量)
                    {
                        eprintln!("[hot-reload] 永続束を再登録できなかった: {誤り}");
                        return;
                    }
                    if let Some(配線) = &mut self.ストリーミング {
                        配線.調停をリセットする();
                    }
                }
            }
            ホットリロード結果::アセット再読込失敗 { 誤り } => {
                eprintln!("[hot-reload] アセットの再読込に失敗した:\n{誤り}");
            }
        }
    }
}

/// 差し替えが成立したときだけ、新しいシーンの登録一式を返す。呼出し側はこの有無でストリーミングと束ごとの台帳のリセットを決める。
fn アセット再読込を反映する(
    レンダラー: &mut blitz_render::レンダラー,
    シーン: &blitz_engine::シーンデータ,
    並べ方: crate::cli::描画対象の並べ方,
    大域平行移動: blitz_math::大域ワールド位置,
    ゲーム配線: &crate::game::ゲーム配線,
) -> Option<super::scene_load::束の登録一式> {
    // 再読込の対象は起動時シーンであり、束の入れ替えを伴わないため所有チャンクは起動時と同じ原点チャンクである。
    let 束座標 = super::scene_load::起動時シーンの所有チャンク;
    match super::scene_load::シーンをレンダラー入力に変換する(シーン, 並べ方, 束座標, 大域平行移動) {
        Ok(mut 描画入力) => {
            // 差し替えでも動く個体を宣言し直す。宣言を落とすと、再読込の後だけ供給の届かない静的な個体変換になり、キツネが止まる。
            if let Err(誤り) =
                ゲーム配線.束の描画シーン素材へ動く個体を宣言する(super::scene_load::起動時シーンの束ID, &mut 描画入力.描画シーン)
            {
                eprintln!("[hot-reload] 再読込したシーンへ動く個体を宣言できなかった: {誤り}");
                return None;
            }
            match レンダラー.シーンを差し替える(描画入力.描画シーン) {
                Ok(()) => Some(描画入力.登録一式),
                Err(誤り) => {
                    eprintln!("[hot-reload] シーン差し替えに失敗した: {誤り}");
                    None
                }
            }
        }
        Err(誤り) => {
            eprintln!("[hot-reload] 再読込したシーンの変換に失敗した: {誤り}");
            None
        }
    }
}
