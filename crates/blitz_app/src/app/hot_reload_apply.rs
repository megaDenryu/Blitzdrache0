//! ホットリローダーの確認結果(シェーダー再コンパイル・アセット再読込)をレンダラーへ反映する。
//! 触れるフィールドは`ホットリローダー`・`レンダラー`に限る。実行時アセット一式の反映は`hot_reload_asset_apply`が所有する。
//! 呼び出しタイミング: `frame`の`一フレーム実行する`の冒頭で、その回の入力確定より前に呼ぶ(差し替えを同じフレームの描画から効かせるため)。

use super::アプリ;
use crate::hot_reload::ホットリロード結果;

/// 契約別のシェーダー束でシーンのパイプライン表を交換できたときに1回だけ出す行。
const 差し替え成功の行: &str = "[hot-reload] 契約別のシェーダー束でシーンのパイプラインを差し替えた";

impl アプリ {
    pub(super) fn ホットリロードを確認する(&mut self) {
        let 結果 = self.ホットリローダー.確認する();
        // 再読込は成否によらずディスクを読む。読んだ事実をここで数える。
        if matches!(
            結果,
            ホットリロード結果::アセット再読込成功 { .. } | ホットリロード結果::アセット再読込失敗 { .. }
        ) {
            self.シーン読込計数.読み込んだ(self.現在フレーム);
        }
        match 結果 {
            ホットリロード結果::変化なし => {}
            ホットリロード結果::シェーダー再コンパイル成功 { シェーダー } => {
                let Some(レンダラー) = &mut self.レンダラー else {
                    return;
                };
                match レンダラー.シェーダーを差し替える(シェーダー) {
                    // 注意: この行の綴りは`cargo xtask shader-reload-draw`が数える。差し替えが1度も起きなかった実行を
                    // 「絵が変わらなかった」だけで通さないための計数であり、文面を変えるときは検収側も同時に直す。
                    Ok(()) => println!("{}", 差し替え成功の行),
                    Err(誤り) => eprintln!("[hot-reload] パイプライン差し替えに失敗した: {誤り}"),
                }
            }
            ホットリロード結果::シェーダー再コンパイル失敗 { 誤り } => {
                eprintln!("[hot-reload] シェーダーの再コンパイルに失敗した:\n{誤り}");
            }
            ホットリロード結果::アセット再読込成功 { 一式 } => {
                self.公開済みの実行時アセット一式を反映する(*一式)
            }
            ホットリロード結果::アセット再読込失敗 { 誤り } => {
                eprintln!("[hot-reload] アセットの再読込に失敗した:\n{誤り}");
            }
        }
    }
}
