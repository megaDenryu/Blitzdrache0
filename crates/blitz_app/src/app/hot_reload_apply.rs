//! ホットリローダーの確認結果(シェーダー再コンパイル・アセット再読込)をレンダラーへ反映する。
//! 触れるフィールドは`ホットリローダー`・`レンダラー`・`描画対象数`・`大域オフセット`・`ストリーミング`に限る。
//! 呼び出しタイミング: `frame`の`一フレーム実行する`の冒頭で、その回の入力確定より前に呼ぶ(差し替えを同じフレームの描画から効かせるため)。

use super::アプリ;
use crate::hot_reload::ホットリロード結果;

impl アプリ {
    pub(super) fn ホットリロードを確認する(&mut self) {
        let 結果 = self.ホットリローダー.確認する();
        // 再読込は成否によらずディスクを読む。読んだ事実をここで数える。
        if matches!(
            結果,
            ホットリロード結果::アセット再読込成功 { .. } | ホットリロード結果::アセット再読込失敗 { .. }
        ) {
            self.シーン読込計数.読み込んだ(self.現在フレーム);
        }
        let 描画対象数 = self.描画対象数;
        let 大域オフセット = self.大域オフセット;
        let Some(レンダラー) = &mut self.レンダラー else {
            return;
        };
        match 結果 {
            ホットリロード結果::変化なし => {}
            ホットリロード結果::シェーダー再コンパイル成功 { シェーダー } => {
                if let Err(誤り) = レンダラー.シェーダーを差し替える(シェーダー) {
                    eprintln!("[hot-reload] パイプライン差し替えに失敗した: {誤り}");
                }
            }
            ホットリロード結果::シェーダー再コンパイル失敗 { メッセージ } => {
                eprintln!("[hot-reload] シェーダーの再コンパイルに失敗した:\n{メッセージ}");
            }
            ホットリロード結果::アセット再読込成功 { シーン } => {
                // シーン差し替えが成功したときだけ調停と可視材料をリセットする。失敗したときは従来の描画束がそのまま残っており、台帳と乖離しない。
                if let Some(可視材料一覧) = アセット再読込を反映する(レンダラー, &シーン, 描画対象数, 大域オフセット)
                {
                    self.可視判定.全束を解除する();
                    self.可視判定.束を登録する(super::scene_load::起動時シーンの束ID, 可視材料一覧);
                    if let Some(配線) = &mut self.ストリーミング {
                        配線.調停をリセットする();
                    }
                }
            }
            ホットリロード結果::アセット再読込失敗 { メッセージ } => {
                eprintln!("[hot-reload] アセットの再読込に失敗した:\n{メッセージ}");
            }
        }
    }
}

/// 差し替えが成立したときだけ、新しいシーンの可視材料を返す。呼出し側はこの有無でストリーミングと可視材料のリセットを決める。
fn アセット再読込を反映する(
    レンダラー: &mut blitz_render::レンダラー,
    シーン: &blitz_engine::シーンデータ,
    描画対象数: Option<crate::cli::描画対象数>,
    大域平行移動: blitz_math::大域ワールド位置,
) -> Option<Vec<super::visibility::群可視材料の登録>> {
    // 再読込の対象は起動時シーンであり、束の入れ替えを伴わないため所有チャンクは起動時と同じ原点チャンクである。
    let 束座標 = super::scene_load::起動時シーンの所有チャンク;
    match super::scene_load::シーンをレンダラー入力に変換する(シーン, 描画対象数, 束座標, 大域平行移動) {
        Ok(描画入力) => match レンダラー.シーンを差し替える(描画入力.描画シーン) {
            Ok(()) => Some(描画入力.可視材料一覧),
            Err(誤り) => {
                eprintln!("[hot-reload] シーン差し替えに失敗した: {誤り}");
                None
            }
        },
        Err(誤り) => {
            eprintln!("[hot-reload] 再読込したシーンの変換に失敗した: {誤り}");
            None
        }
    }
}
