//! 起動から終了まで常駐する束0と遠景束1を、レンダラーと2つのアプリ台帳へ一括登録する。

use blitz_render::{レンダラー, 描画束ID, 描画束の影方針};

use super::primitive_draw_item_registry::プリミティブ描画項目台帳;
use super::scene_load::{束の描画入力, 束の登録一式};
use super::visibility::可視判定配線;
use crate::error::起動エラー;

pub(super) const 遠景の束ID: 描画束ID = 描画束ID::生成する(1);

#[derive(Default)]
pub(super) struct 永続束の状態 {
    pub(super) 遠景シーン: Option<blitz_engine::シーンデータ>,
    pub(super) 遠景をレンダラーへ登録済み: bool,
}

pub(super) fn 登録する(
    レンダラー: &mut レンダラー,
    可視判定: &mut 可視判定配線,
    項目台帳: &mut プリミティブ描画項目台帳,
    起動時: 束の登録一式,
    遠景: Option<束の描画入力>,
    遠景登録済み: &mut bool,
) -> Result<(), 起動エラー> {
    可視判定.全束を解除する();
    項目台帳.全束を解除する();
    台帳へ登録する(可視判定, 項目台帳, super::scene_load::起動時シーンの束ID, 起動時);
    if let Some(遠景) = 遠景 {
        if !*遠景登録済み {
            レンダラー.影方針つき描画束を追加する(遠景の束ID, &遠景.描画シーン, 描画束の影方針::最遠距離区分だけ)?;
            *遠景登録済み = true;
        }
        台帳へ登録する(可視判定, 項目台帳, 遠景の束ID, 遠景.登録一式);
    }
    Ok(())
}

pub(super) fn 再登録する(
    レンダラー: &mut レンダラー,
    可視判定: &mut 可視判定配線,
    項目台帳: &mut プリミティブ描画項目台帳,
    起動時: 束の登録一式,
    状態: &mut 永続束の状態,
    大域平行移動: blitz_math::大域ワールド位置,
) -> Result<(), 起動エラー> {
    let 遠景 = 状態
        .遠景シーン
        .as_ref()
        .map(|シーン| {
            super::scene_load::シーンをレンダラー入力に変換する(
                シーン,
                crate::cli::描画対象の並べ方::そのまま読む(),
                super::scene_load::起動時シーンの所有チャンク,
                大域平行移動,
            )
        })
        .transpose()?;
    登録する(レンダラー, 可視判定, 項目台帳, 起動時, 遠景, &mut 状態.遠景をレンダラーへ登録済み)
}

fn 台帳へ登録する(
    可視判定: &mut 可視判定配線, 項目台帳: &mut プリミティブ描画項目台帳, 束id: 描画束ID, 登録: 束の登録一式
) {
    可視判定.束を登録する(束id, 登録.可視材料一覧);
    項目台帳.束を登録する(束id, 登録.プリミティブ描画項目一覧);
}
