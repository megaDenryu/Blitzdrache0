//! 起動から終了まで常駐する束0と遠景束1を、レンダラーと2つのアプリ台帳へ登録するサービス型。
//!
//! 遠景のシーン・レンダラーへ登録済みかの旗・影方針の3つを1つの型が所有する。3つは常に組で動くためである。
//! シーンだけを外から差し替えると旗が「登録済み」のまま残り、次の再登録が新しいシーンをレンダラーへ渡さない。
//! 旗だけを外から下ろすと、同じ束IDが2度追加される。組で動く不変条件を型の外へ出すと、外側の代入の順序が
//! その不変条件を担うことになり、順序を1つ入れ替えただけで壊れる。
//!
//! 登録を自由関数でなくメソッドにするのは、レンダラー・可視判定・項目台帳の3つを呼び出し側に持参させないため
//! である(参照: グローバルCLAUDE.md「サービスの依存保持とコールバックの限定」)。3つはこの型が保持できない
//! (どれもアプリの他の局面が所有する)ため引数で受けるが、旗とシーンという自分の状態は自分が持つ。

mod placement;

use blitz_render::{レンダラー, 描画束ID, 描画束の影方針};

use super::primitive_draw_item_registry::プリミティブ描画項目台帳;
use super::scene_load::{束の描画入力, 束の登録一式};
use super::visibility::可視判定配線;
use crate::error::起動エラー;

pub(super) const 遠景の束ID: 描画束ID = 描画束ID::生成する(1);

/// 常駐する束の状態。遠景を持たない世界では遠景シーンが無いまま起動から終了まで動く。
pub(super) struct 永続束の状態 {
    遠景シーン: Option<blitz_engine::シーンデータ>,
    遠景をレンダラーへ登録済み: bool,
    遠景の影方針: 描画束の影方針,
}

impl 永続束の状態 {
    pub(super) fn 生成する(影キャスター有効: bool) -> Self {
        let 遠景の影方針 = if 影キャスター有効 {
            描画束の影方針::最遠距離区分だけ
        } else {
            描画束の影方針::描かない
        };
        Self {
            遠景シーン: None,
            遠景をレンダラーへ登録済み: false,
            遠景の影方針,
        }
    }

    /// 起動時に1度だけ、遠景のシーンと描画入力を受け取って登録する。シーンを預かるのと登録するのを同じ呼び出しで
    /// 行うのは、2つが別々に起きると旗とシーンが食い違うためである。
    pub(super) fn 起動時に登録する(
        &mut self,
        レンダラー: &mut レンダラー,
        可視判定: &mut 可視判定配線,
        項目台帳: &mut プリミティブ描画項目台帳,
        起動時: 束の登録一式,
        遠景: Option<(blitz_engine::シーンデータ, 束の描画入力)>,
    ) -> Result<(), 起動エラー> {
        let (遠景シーン, 遠景入力) = match 遠景 {
            Some((シーン, 入力)) => (Some(シーン), Some(入力)),
            None => (None, None),
        };
        self.束を据える(レンダラー, 可視判定, 項目台帳, 起動時, 遠景入力)?;
        self.遠景シーン = 遠景シーン;
        Ok(())
    }

    /// ホットリロードでシーンを読み直した後に、預かってある遠景から描画入力を作り直して登録し直す。
    pub(super) fn 再登録する(
        &mut self,
        レンダラー: &mut レンダラー,
        可視判定: &mut 可視判定配線,
        項目台帳: &mut プリミティブ描画項目台帳,
        起動時: 束の登録一式,
        大域平行移動: blitz_math::大域ワールド位置,
        チャンク一辺: Option<blitz_engine::チャンク一辺>,
    ) -> Result<(), 起動エラー> {
        let 遠景 = self
            .遠景シーン
            .as_ref()
            .map(|シーン| {
                super::scene_load::シーンをレンダラー入力に変換する(
                    シーン,
                    crate::cli::描画対象の並べ方::そのまま読む(),
                    super::scene_load::起動時シーンの所有チャンク,
                    大域平行移動,
                    チャンク一辺,
                )
            })
            .transpose()?;
        self.束を据える(レンダラー, 可視判定, 項目台帳, 起動時, 遠景)
    }
}
