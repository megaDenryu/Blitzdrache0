//! 描画束の台帳。1つの描画束を成す4つ(束ごとの可視材料・束ごとのプリミティブ描画項目・常駐する束の状態・
//! 世界に1つだけ置く地表の層のタイル)を1つの型が持つ。束の登録と解除は起動時・ホットリロード・ストリーミングの
//! 3箇所で必ず一体に動き、どれか1つだけを外から触ると、レンダラーが描く束と台帳の中身が食い違う。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断11」
//!
//! レンダラーはこの型が保持しない。破棄順の不変条件を`画面の据え付け`が持つためである。`大域ずらし量`も保持しない。
//! 起動時に決まる写せる定数であり、私有にすると取り出す口が生えるためである。どちらも引数で受ける。
//! 起動時とホットリロードの据え付けは`installation`、描画入力が借りる受け皿は`tray`が持つ。

mod installation;
mod tray;

use blitz_math::{クリップ, ワールド, 変換, 大域ワールド位置};
use blitz_render::{ライティング入力, 描画束ID};

use super::persistent_bundles::永続束の状態;
use super::primitive_draw_item_registry::プリミティブ描画項目台帳;
use super::scene_load::{シーンを描画入力へ写す材料, 地表の層のタイル一式, 束の登録一式};
use super::visibility::{可視判定配線, 選別のつまみ, 選別の計器};
use crate::error::起動エラー;

pub(in crate::app) use installation::起動時シーンの差し替え材料;

pub(in crate::app) struct 描画束の台帳 {
    可視判定: 可視判定配線,
    プリミティブ描画項目: プリミティブ描画項目台帳,
    永続束: 永続束の状態,
    地表の層のタイル: 地表の層のタイル一式, // カタログを読むまで決まらず、束を写すたびに引かれる
}

impl 描画束の台帳 {
    pub(in crate::app) fn 生成する(つまみ: 選別のつまみ, 遠景影キャスター有効: bool) -> Self {
        Self {
            可視判定: 可視判定配線::生成する(つまみ),
            プリミティブ描画項目: プリミティブ描画項目台帳::default(),
            永続束: 永続束の状態::生成する(遠景影キャスター有効),
            地表の層のタイル: 地表の層のタイル一式::タイルを持たない世界,
        }
    }

    /// その世代の層のタイルを据える。以後の束の変換はこの世代のタイルを引く。
    pub(in crate::app) fn 地表の層のタイルを据える(&mut self, タイル: 地表の層のタイル一式) {
        self.地表の層のタイル = タイル;
    }

    /// 束の変換へ渡す材料を、自分が持つ層のタイルから組む。綴りを台帳の中の1箇所へ閉じるためである。
    pub(in crate::app) fn シーンを写す材料を組む(&self, 大域ずらし量: 大域ワールド位置, チャンク一辺: Option<blitz_engine::チャンク一辺>) -> シーンを描画入力へ写す材料<'_> {
        シーンを描画入力へ写す材料::生成する(大域ずらし量, チャンク一辺, &self.地表の層のタイル)
    }

    /// レンダラーへ束を追加した直後に呼ぶ。2つの台帳は同じ束IDで対になるため、片方だけの登録を外から書けないようにする。
    pub(in crate::app) fn 束を登録する(&mut self, 束id: 描画束ID, 登録: 束の登録一式) {
        self.可視判定.束を登録する(束id, 登録.可視材料一覧);
        self.プリミティブ描画項目.束を登録する(束id, 登録.プリミティブ描画項目一覧);
    }

    /// レンダラーが束を描かなくなる時点で呼ぶ。残すと、存在しない束の選択と発行を毎フレーム作り続ける。
    pub(in crate::app) fn 束を解除する(&mut self, 束id: 描画束ID) {
        self.可視判定.束を解除する(束id);
        self.プリミティブ描画項目.束を解除する(束id);
    }

    /// カメラ更新の後、描画入力の組み立てより前に呼ぶ。
    pub(in crate::app) fn この描画の可視個体を選別する(
        &mut self, ビュー射影: 変換<ワールド, クリップ>, ライティング: ライティング入力, カメラ大域位置: 大域ワールド位置
    ) -> Result<(), 起動エラー> {
        self.可視判定.判定する(ビュー射影, ライティング, カメラ大域位置)
    }

    /// 起動から現在までに個体の段が入れ替わった延べ回数。
    pub(in crate::app) fn 個体詳細段切替回数(&self) -> u64 {
        self.可視判定.段切替回数()
    }

    /// 可視判定と段選択へ登録されている群の件数。束の解除で材料と段の記憶が漏れなく消えたことをこの数で見る。
    pub(in crate::app) fn 可視材料登録数(&self) -> usize {
        self.可視判定.登録数()
    }

    /// 直近のフレームの選別の計器。計数・解像度密度・距離分布を一組で返す。
    pub(in crate::app) fn 直近の選別の計器(&self) -> 選別の計器 {
        self.可視判定.直近の計器()
    }
}
