//! 起動時に、要求された報告に対応するレンダラー側の計測だけを有効にする配線。

use blitz_render::{レンダラー, 実表示計測状況, 実表示計測要求};

use super::frame_timing::{ウォームアップフレーム数, 標本容量};

/// レンダラー生成時に渡す要求。拡張の有効化自体が提示ペーシングを変えるため、
/// `--report-display-timing`が無いときは拡張へ触れさせない。
pub(super) fn 実表示計測要求を決める(アプリ: &super::アプリ) -> 実表示計測要求 {
    if アプリ.報告要求.実表示時間 {
        実表示計測要求::要求する
    } else {
        実表示計測要求::要求しない
    }
}

/// 注意: 実表示計測はCPU区間計測と独立に切り替える。実表示計測は`vkWaitForPresentKHR`で描画ループを
/// 止めるため、フレーム時間報告に相乗りさせると素の条件のフレーム間隔が二度と測れなくなる。
/// 戻り値は実表示計測を有効にしたときだけ`Some`で、その対応状況を表す。
pub(super) fn レンダラーの計測を有効にする(
    レンダラー: &mut レンダラー, アプリ: &super::アプリ
) -> Option<実表示計測状況> {
    let 標本容量 = 標本容量(アプリ.起動モード);
    // 区間の内訳はレンダラーの同じ計測から出るため、フレーム時間報告と区間報告のどちらでも有効にする。
    if アプリ.フレーム間隔計測.is_some() || アプリ.群選択計測.is_some() {
        レンダラー.cpu区間計測を有効にする(ウォームアップフレーム数, 標本容量);
    }
    if !アプリ.報告要求.実表示時間 {
        return None;
    }
    Some(レンダラー.実表示計測を有効にする(ウォームアップフレーム数, 標本容量))
}
