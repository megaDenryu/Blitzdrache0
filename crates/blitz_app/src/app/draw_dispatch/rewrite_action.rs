//! スモーク計画が要求したシェーダーまたはアセットの書き換えを適用する。

use super::super::アプリ;
use crate::error::起動エラー;
use crate::smoke::{self, スモークアクション};

pub(super) fn 適用する(アプリ: &アプリ, アクション: スモークアクション) -> Result<(), 起動エラー> {
    match アクション {
        スモークアクション::シェーダー書き換え => smoke::シェーダーを書き換える(&アプリ.シェーダー監視パス),
        スモークアクション::アセット書き換え => smoke::アセットを書き換える(&アプリ.アセットルート, &アプリ.シーン),
        _ => Ok(()),
    }
}
