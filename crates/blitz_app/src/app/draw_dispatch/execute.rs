//! 組み立て済みの描画入力をスモークアクションに応じた経路へ渡して実行する工程。受け取るのはアクションと
//! 描画入力、返すのはそのフレームが提示へ到達したかである。
//!
//! 到達を返すのは、焼き直しの鍵を確定してよいかを呼び出し元が決めるためである。読み戻しを伴う判定の経路は
//! 見送りをそのまま失敗にするため、`Ok`で戻った時点で提示へ到達している。

use blitz_render::{フレーム描画入力, 描画結果, 読み戻し結果};

use super::frame_reach::描画の到達;
use super::{pixel_readback, rewrite_action};
use crate::app::アプリ;
use crate::error::起動エラー;
use crate::smoke::{self, スモークアクション};

impl アプリ {
    pub(in crate::app) fn 実行して判定する(
        &mut self,
        アクション: スモークアクション,
        描画入力: フレーム描画入力<'_>,
    ) -> Result<描画の到達, 起動エラー> {
        rewrite_action::適用する(self, アクション)?;

        let Some(レンダラー) = &mut self.レンダラー else {
            return Ok(描画の到達::届かなかった);
        };

        match アクション {
            スモークアクション::初期色判定
            | スモークアクション::アセット反映後判定
            | スモークアクション::最終判定
            | スモークアクション::ヘルメット判定
            | スモークアクション::粒子判定
            | スモークアクション::開発UI判定
            | スモークアクション::シャドウ判定
            | スモークアクション::複数描画対象判定 => {
                pixel_readback::画素を判定する(レンダラー, 描画入力, アクション)?;
                Ok(描画の到達::提示した)
            }
            // foxステージ(判断45): 基準フレームを保存し、後続フレームとの差分でアニメーションの動きを判定する。
            スモークアクション::フォックス基準保存 => match レンダラー.一フレーム描画して読み戻す(描画入力)? {
                読み戻し結果::読み戻した(画像) => {
                    self.スモーク基準画像 = Some(画像);
                    Ok(描画の到達::提示した)
                }
                読み戻し結果::見送った(理由) => Err(起動エラー::ピクセル判定失敗(
                    format!("基準フレームで描画が見送られた: {理由:?}"),
                )),
            },
            スモークアクション::フォックス差分判定 => self.フォックス差分を判定する(描画入力),
            _ => Ok(到達へ写す(レンダラー.一フレーム描画する(描画入力)?)),
        }
    }

    fn フォックス差分を判定する(&mut self, 描画入力: フレーム描画入力<'_>) -> Result<描画の到達, 起動エラー> {
        let Some(レンダラー) = &mut self.レンダラー else {
            return Ok(描画の到達::届かなかった);
        };
        let 読み戻し = レンダラー.一フレーム描画して読み戻す(描画入力)?;
        let Some(基準) = &self.スモーク基準画像 else {
            return Err(起動エラー::ピクセル判定失敗(
                "差分判定前に基準画像が保存されていない".to_string(),
            ));
        };
        match 読み戻し {
            読み戻し結果::読み戻した(画像) => {
                smoke::アニメーション差分を判定する(基準, &画像)?;
                Ok(描画の到達::提示した)
            }
            読み戻し結果::見送った(理由) => Err(起動エラー::ピクセル判定失敗(
                format!("差分判定フレームで描画が見送られた: {理由:?}"),
            )),
        }
    }
}

fn 到達へ写す(結果: 描画結果) -> 描画の到達 {
    match 結果 {
        描画結果::提示した => 描画の到達::提示した,
        描画結果::見送った(_) => 描画の到達::届かなかった,
    }
}
