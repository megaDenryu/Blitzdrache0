//! 時間再構成の観測を採る工程。受け取るのはそのフレームの描画入力、返すのはそのフレームが提示へ到達したかである。
//!
//! 観測の期間を最後の何フレームかに限るのは、それより前のフレームでは大気と間接照明の焼き上げが進行中で、
//! この観測と無関係な要因で絵が動くためである。期間を画素内ずらしの列の長さの倍数に採るのは、
//! 定常状態が列の長さを周期とする周期軌道であり、周期の全体を跨がないとフレーム間差分の上限を見誤るためである。
//!
//! 最終フレームだけ3回描くのは、履歴を無効にした直後の1フレーム目の結果と、そのフレームの今の色を
//! 別々の画像から読み戻すためである。同じ描画入力を渡すため、3回の画素内ずらしもカメラも同じであり、
//! 3枚の間で変わるのは履歴の中身だけになる(`参照: _doc/設計/時間再構成.md`「検収戦略(判断g)」)。

mod readback;

use blitz_engine::temporal_reconstruction::ずらしの列の添字;
use blitz_render::{HDR読み戻し画像, フレーム描画入力};

use super::frame_reach::描画の到達;
use crate::app::アプリ;
use crate::cli::起動モード;
use crate::error::起動エラー;
use crate::reports::temporal_reconstruction;
use crate::smoke::スモークアクション;
use readback::{今のフレームの色を読み戻す, 圧縮前のhdrを読み戻す};

/// 観測を採るフレーム数。列の長さの2周ぶんであり、周期の全体を2度見る。
const 観測フレーム数: u32 = 16;

/// フレームをまたいで持つ観測の材料。前のフレームの結果だけであり、判定も閾値も持たない。
pub(in crate::app) struct 時間再構成の観測 {
    前フレームの結果: Option<HDR読み戻し画像>,
}

impl 時間再構成の観測 {
    pub(in crate::app) fn 記録なしで生成する() -> Self {
        Self {
            前フレームの結果: None
        }
    }
}

impl アプリ {
    /// このフレームで時間再構成の観測を採るか。`--report-temporal-reconstruction`を与えた`--frames`の
    /// 最後の何フレームかだけが対象である。
    pub(in crate::app) fn 時間再構成を観測するフレームか(&self, アクション: スモークアクション) -> bool {
        if !self.読み戻し検収.時間再構成を報告するか {
            return false;
        }
        let 起動モード::スモーク実行 { フレーム数 } = self.起動モード else {
            return false;
        };
        if アクション == スモークアクション::差し替え前ダンプ {
            return false;
        }
        self.現在フレーム + 観測フレーム数.min(フレーム数) >= フレーム数
    }

    pub(in crate::app) fn 時間再構成を観測する(
        &mut self, 描画入力: フレーム描画入力<'_>
    ) -> Result<描画の到達, 起動エラー> {
        let 起動モード::スモーク実行 { フレーム数 } = self.起動モード else {
            return Ok(描画の到達::届かなかった);
        };
        if self.現在フレーム + 1 == フレーム数 {
            return self.無効化直後を突き合わせる(描画入力);
        }
        self.フレーム間差分を採る(描画入力)
    }

    /// 1フレーム描いて再構成後の結果を読み戻し、前のフレームの結果との差を並べる。
    fn フレーム間差分を採る(&mut self, 描画入力: フレーム描画入力<'_>) -> Result<描画の到達, 起動エラー> {
        let 現在フレーム = self.現在フレーム;
        let Some(今の結果) = 圧縮前のhdrを読み戻す(self, 描画入力, "フレーム間差分")? else {
            return Ok(描画の到達::届かなかった);
        };
        if let Some(前) = &self.時間再構成の観測.前フレームの結果 {
            temporal_reconstruction::フレーム間差分を報告する(現在フレーム, 前, &今の結果);
        }
        self.時間再構成の観測.前フレームの結果 = Some(今の結果);
        Ok(描画の到達::提示した)
    }

    /// 履歴を無効にしてから3回描き、無効化直後の結果と今の色の一致、および決定性の要約値を出す。
    fn 無効化直後を突き合わせる(&mut self, 描画入力: フレーム描画入力<'_>) -> Result<描画の到達, 起動エラー> {
        if let Some(レンダラー) = &mut self.レンダラー {
            レンダラー.時間再構成の履歴を無効にする();
        }
        let Some(無効化直後) = 圧縮前のhdrを読み戻す(self, 描画入力.clone(), "無効化直後")? else {
            return Ok(描画の到達::届かなかった);
        };
        let Some(今の色) = 今のフレームの色を読み戻す(self, 描画入力.clone(), "今のフレームの色")? else {
            return Ok(描画の到達::届かなかった);
        };
        temporal_reconstruction::無効化直後を報告する(&無効化直後, &今の色);
        let Some(履歴を混ぜた結果) = 圧縮前のhdrを読み戻す(self, 描画入力, "要約")? else {
            return Ok(描画の到達::届かなかった);
        };
        temporal_reconstruction::要約を報告する(&履歴を混ぜた結果);
        println!("[temporal-reconstruction] 列の長さ{}", ずらしの列の添字::列の長さ());
        Ok(描画の到達::提示した)
    }
}
