//! 時間再構成の観測を採る工程。受け取るのはそのフレームの描画入力、返すのはそのフレームが提示へ到達したかである。
//!
//! どのフレームで観測を採り、どちらの局面かは`検収の起動設定`の経路の判定が決める。
//!
//! 最終フレームだけ3回描くのは、履歴を無効にした直後の1フレーム目の結果と、そのフレームの今の色を
//! 別々の画像から読み戻すためである。同じ描画入力を渡すため、3回の画素内ずらしもカメラも同じであり、
//! 3枚の間で変わるのは履歴の中身だけになる(`参照: _doc/設計/時間再構成.md`「検収戦略(判断g)」)。

mod readback;

use blitz_engine::temporal_reconstruction::ずらしの列の添字;
use blitz_render::{HDR読み戻し画像, フレーム描画入力};

use super::frame_reach::描画の到達;
use crate::app::screen_installation::画面の据え付け;
use crate::app::time_step::フレーム番号;
use crate::app::verification_launch_settings::時間再構成の観測の局面;
use crate::app::アプリ;
use crate::error::起動エラー;
use crate::reports::temporal_reconstruction;
use readback::{今のフレームの色を読み戻す, 圧縮前のhdrを読み戻す};

/// フレームをまたいで持つ観測の材料。前のフレームの結果だけであり、判定も閾値も持たない。
pub(in crate::app) struct 時間再構成の観測 {
    前フレームの結果: Option<HDR読み戻し画像>,
}

impl 時間再構成の観測 {
    pub(in crate::app) fn 記録なしで生成する() -> Self {
        Self { 前フレームの結果: None }
    }
}

impl アプリ {
    pub(in crate::app) fn 時間再構成を観測する(&mut self, 描画入力: フレーム描画入力<'_>, 局面: 時間再構成の観測の局面, フレーム番号: フレーム番号) -> Result<描画の到達, 起動エラー> {
        match 局面 {
            時間再構成の観測の局面::無効化直後 => self.無効化直後を突き合わせる(描画入力),
            時間再構成の観測の局面::フレーム間差分 => self.フレーム間差分を採る(描画入力, フレーム番号),
        }
    }

    /// 1フレーム描いて再構成後の結果を読み戻し、前のフレームの結果との差を並べる。
    fn フレーム間差分を採る(&mut self, 描画入力: フレーム描画入力<'_>, フレーム番号: フレーム番号) -> Result<描画の到達, 起動エラー> {
        let レンダラー = 画面の据え付け::描画の最中に借りる(&mut self.据え付け).レンダラーを借りる();
        let Some(今の結果) = 圧縮前のhdrを読み戻す(レンダラー, 描画入力, "フレーム間差分")? else {
            return Ok(描画の到達::届かなかった);
        };
        if let Some(前) = &self.時間再構成の観測.前フレームの結果 {
            temporal_reconstruction::フレーム間差分を報告する(フレーム番号, 前, &今の結果);
        }
        self.時間再構成の観測.前フレームの結果 = Some(今の結果);
        Ok(描画の到達::提示した)
    }

    /// 履歴を無効にしてから3回描き、無効化直後の結果と今の色の一致、および決定性の要約値を出す。
    fn 無効化直後を突き合わせる(&mut self, 描画入力: フレーム描画入力<'_>) -> Result<描画の到達, 起動エラー> {
        let 据え付け = 画面の据え付け::描画の最中に借りる(&mut self.据え付け);
        据え付け.レンダラーを借りる().時間再構成の履歴を無効にする();
        let Some(無効化直後) = 圧縮前のhdrを読み戻す(据え付け.レンダラーを借りる(), 描画入力.clone(), "無効化直後")? else {
            return Ok(描画の到達::届かなかった);
        };
        let Some(今の色) = 今のフレームの色を読み戻す(据え付け.レンダラーを借りる(), 描画入力.clone(), "今のフレームの色")? else {
            return Ok(描画の到達::届かなかった);
        };
        temporal_reconstruction::無効化直後を報告する(&無効化直後, &今の色);
        let Some(履歴を混ぜた結果) = 圧縮前のhdrを読み戻す(据え付け.レンダラーを借りる(), 描画入力, "要約")? else {
            return Ok(描画の到達::届かなかった);
        };
        temporal_reconstruction::要約を報告する(&履歴を混ぜた結果);
        println!("[temporal-reconstruction] 列の長さ{}", ずらしの列の添字::列の長さ());
        Ok(描画の到達::提示した)
    }
}
