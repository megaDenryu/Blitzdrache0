//! 区画と画素の位置から、合成入力の色を決める工程。受け取るのは画素の位置、返すのは3成分の色である。
//!
//! 独立した工程にするのは、2つの色が「半精度で正確に表せる数だけを使う」という同じ制約を負い、その制約を
//! 守っているかを1つのファイルで読めるようにするためである。刻みを1/32と1/16に採るのは、どちらも2の冪であり
//! 半精度の仮数で正確に表せるためである。

/// 画素ごとに変える今のフレームの色。
/// 区画の中で値を変えるのは、3x3の近傍が張る範囲を退化させないためである。退化すると収めが履歴を今の色へ潰し、混合を検査できない。
pub(super) fn 今のフレームの色を決める(横: u32, 縦: u32) -> [f32; 3] {
    let 刻み = 1.0 / 32.0;
    [
        小さい整数へ(横 % 8 + 1) * 刻み,
        小さい整数へ(縦 % 8 + 1) * 刻み,
        小さい整数へ((横 + 縦) % 8 + 1) * 刻み,
    ]
}

/// 区画ごとに変える履歴の色。今のフレームの色より広い範囲に採るのは、近傍が張る範囲へ収める操作が実際に働く画素を作るためである。
pub(super) fn 履歴の色を決める(横: u32, 縦: u32) -> [f32; 3] {
    let 刻み = 1.0 / 16.0;
    let 区画横 = 横 / super::区画の一辺;
    let 区画縦 = 縦 / super::区画の一辺;
    [
        小さい整数へ(区画横 % 13 + 1) * 刻み,
        小さい整数へ(区画縦 % 11 + 1) * 刻み,
        小さい整数へ((区画横 + 区画縦) % 7 + 1) * 刻み,
    ]
}

/// 剰余で作った小さい整数を実数へ写す。剰余の上限が13であるため16ビットへ必ず収まる。
fn 小さい整数へ(値: u32) -> f32 {
    f32::from(u16::try_from(値).unwrap_or(1))
}
