//! 検収が与える合成入力4枚を焼く工程。受け取るのは画面の寸法と射影の復元、返すのは4枚と、画素ごとの区画の別である。
//!
//! 値をすべて半精度で正確に表せる数に採るのは、GPUが半精度の画像へ書き戻した値とCPU正本が使う値を同じにするためである。
//! 入力の側で丸めが起きると、突き合わせの差に「与えた値の違い」が混ざり、写しの誤りだけを取り出せない。
//!
//! 動きベクトルを零か画面の外かの2つに限るのは、Vulkanが線形補間の副画素の精度を8ビットまでしか保証しないためである
//! (`subTexelPrecisionBits`)。零なら参照位置が画素の中心そのものになり、補間の重みが1と0に定まって参照した値が一意に決まる。
//! 端数の位置で参照すると、CPU正本が置く重みとGPUの重みが最大で1/256食い違い、その差が写しの誤りより大きくなる。

use blitz_render::local_visibility::{射影の復元, 画像の寸法};

use value::{今のフレームの色を決める, 履歴の色を決める};

mod value;

/// 区画1つの一辺(画素)。区画ごとに履歴の色と奥行きと動きベクトルを変え、採否の3つの枝をすべて画面に出す。
const 区画の一辺: u32 = 64;
/// 今の奥行き(メートル)。画面のどこでも同じ値にするのは、棄却の判定が5パーセントの境界から遠い所で決まるようにするためである。
const 今の奥行きメートル: f32 = 50.0;
/// 出現領域の区画が持つ前のフレームの奥行き。今の奥行きの2倍であり、5パーセントの許容から桁で離れている。
const 出現領域の奥行き倍率: f32 = 2.0;
/// 画面の外へ写す区画の動きベクトル。正規化装置座標で片側2の広さに対し4動かすため、必ず外へ出る。
const 画面の外への動き: f32 = 4.0;

/// その画素が属する区画の別。CPU正本はこの別を見て期待する枝を決める。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 区画の別 {
    履歴を採る,
    出現領域,
    画面の外,
}

impl 区画の別 {
    fn 画素から決める(横: u32, 縦: u32) -> Self {
        match ((横 / 区画の一辺) + (縦 / 区画の一辺)) % 3 {
            0 => Self::履歴を採る,
            1 => Self::出現領域,
            _ => Self::画面の外,
        }
    }
}

/// 焼いた4枚と、画素ごとの区画の別。
pub(super) struct 合成入力の材料 {
    pub(super) 今のフレームの色: Vec<f32>,
    pub(super) 履歴: Vec<f32>,
    pub(super) 動きベクトル: Vec<f32>,
    pub(super) 深度: Vec<f32>,
    pub(super) 区画一覧: Vec<区画の別>,
}

pub(super) fn 焼く(寸法: 画像の寸法, 射影: 射影の復元) -> 合成入力の材料 {
    let 深度の値 = 射影.深度へ写す(blitz_math::メートル::生成する(今の奥行きメートル));
    let 画素数 = 寸法.画素数();
    let mut 材料 = 合成入力の材料 {
        今のフレームの色: Vec::with_capacity(画素数 * 4),
        履歴: Vec::with_capacity(画素数 * 4),
        動きベクトル: Vec::with_capacity(画素数 * 2),
        深度: vec![深度の値; 画素数],
        区画一覧: Vec::with_capacity(画素数),
    };
    for 縦 in 0..寸法.高さ() {
        for 横 in 0..寸法.幅() {
            一画素を積む(&mut 材料, 横, 縦);
        }
    }
    材料
}

fn 一画素を積む(材料: &mut 合成入力の材料, 横: u32, 縦: u32) {
    let 別 = 区画の別::画素から決める(横, 縦);
    let 色 = 今のフレームの色を決める(横, 縦);
    材料.今のフレームの色.extend_from_slice(&[色[0], 色[1], 色[2], 1.0]);
    let 履歴の色 = 履歴の色を決める(横, 縦);
    let 前の奥行き = match 別 {
        区画の別::出現領域 => 今の奥行きメートル * 出現領域の奥行き倍率,
        区画の別::履歴を採る | 区画の別::画面の外 => 今の奥行きメートル,
    };
    材料.履歴.extend_from_slice(&[履歴の色[0], 履歴の色[1], 履歴の色[2], 前の奥行き]);
    let 動き = if 別 == 区画の別::画面の外 {
        画面の外への動き
    } else {
        0.0
    };
    材料.動きベクトル.extend_from_slice(&[動き, 動き]);
    材料.区画一覧.push(別);
}
