//! 合成入力から1画素ぶんのCPU正本を作る工程。受け取るのは合成入力の材料と画素の位置と画面共通の3つの量、返すのは再構成後の色である。
//!
//! 突き合わせの数え上げと分けるのは、この工程が「正本をどう組み立てるか」だけを持ち、GPUの読み戻しを1つも知らないためである。
//! 合成の順は`blitz_engine::temporal_reconstruction::一画素を再構成する`が持ち、ここは入力を揃えて渡すだけである。

use blitz_engine::temporal_reconstruction::{
    ビュー空間の奥行き, 一画素を再構成する, 今のフレームの寄与率, 出現領域の相対許容, 動きベクトル, 履歴を採るか判定する, 画面上の位置, 線形色,
    近傍の色の範囲,
};
use blitz_math::メートル;
use blitz_render::local_visibility::画像の寸法;

use super::super::synthesis::合成入力の材料;

/// 画面のどこでも同じ3つの量。画素ごとに作り直すと、同じ値を画素数ぶん組み立て直すことになる。
#[derive(Clone, Copy)]
pub(super) struct 判定の材料 {
    pub(super) 今の奥行き: ビュー空間の奥行き,
    pub(super) 許容: 出現領域の相対許容,
    pub(super) 寄与率: 今のフレームの寄与率,
}

pub(super) fn 一画素の正本(材料: &合成入力の材料, 寸法: 画像の寸法, 横: u32, 縦: u32, 判定: 判定の材料) -> 線形色 {
    let 添字 = 寸法.通し番号(横, 縦);
    let 今の色 = 色を読む(&材料.今のフレームの色, 添字);
    let 履歴の色 = 色を読む(&材料.履歴, 添字);
    let 前の奥行き = ビュー空間の奥行きを作る(メートル::生成する(材料.履歴[添字 * 4 + 3]));
    let 前の位置 = 前のフレームの位置(材料, 寸法, 横, 縦, 添字);
    let 採否 = 履歴を採るか判定する(前の位置, 前の奥行き, 判定.今の奥行き, 判定.許容);
    let 近傍 =
        近傍の色の範囲::近傍から求める(&近傍を集める(材料, 寸法, 横, 縦)).unwrap_or_else(|誤り| panic!("合成入力の近傍から範囲を作れない: {誤り}"));
    一画素を再構成する(今の色, 履歴の色, 近傍, 採否, 判定.寄与率).unwrap_or_else(|誤り| panic!("合成入力から一画素を再構成できない: {誤り}"))
}

fn 前のフレームの位置(材料: &合成入力の材料, 寸法: 画像の寸法, 横: u32, 縦: u32, 添字: usize) -> 画面上の位置 {
    let 中心 = 画素の中心(寸法, 横, 縦);
    let 動き = 動きベクトル::生成する(材料.動きベクトル[添字 * 2], 材料.動きベクトル[添字 * 2 + 1])
        .unwrap_or_else(|誤り| panic!("合成入力の動きベクトルが値域を外れた: {誤り}"));
    動き
        .前のフレームの位置(中心)
        .unwrap_or_else(|誤り| panic!("合成入力から前のフレームの位置を作れない: {誤り}"))
}

/// 画素の中心の正規化装置座標。式の並びは`shaders/temporal_reconstruction_setting.slang`の写しと同じ順である。
fn 画素の中心(寸法: 画像の寸法, 横: u32, 縦: u32) -> 画面上の位置 {
    let 横の位置 = 2.0 * (実数へ(横) + 0.5) / 実数へ(寸法.幅()) - 1.0;
    let 縦の位置 = 2.0 * (実数へ(縦) + 0.5) / 実数へ(寸法.高さ()) - 1.0;
    画面上の位置::生成する(横の位置, 縦の位置).unwrap_or_else(|誤り| panic!("画素の中心が値域を外れた: {誤り}"))
}

/// その画素を中心とする3x3の近傍。範囲の外へはみ出す位置は端の画素へ張り付ける(slangの写しと同じ規則)。
fn 近傍を集める(材料: &合成入力の材料, 寸法: 画像の寸法, 横: u32, 縦: u32) -> Vec<線形色> {
    let mut 近傍 = Vec::with_capacity(9);
    for 縦の差 in [-1_i32, 0, 1] {
        for 横の差 in [-1_i32, 0, 1] {
            let 位置横 = 張り付ける(横, 横の差, 寸法.幅());
            let 位置縦 = 張り付ける(縦, 縦の差, 寸法.高さ());
            近傍.push(色を読む(&材料.今のフレームの色, 寸法.通し番号(位置横, 位置縦)));
        }
    }
    近傍
}

fn 張り付ける(位置: u32, 差: i32, 上限: u32) -> u32 {
    let 移動後 = i64::from(位置) + i64::from(差);
    let 上端 = i64::from(上限) - 1;
    u32::try_from(移動後.clamp(0, 上端)).unwrap_or(0)
}

fn 色を読む(成分列: &[f32], 添字: usize) -> 線形色 {
    線形色::生成する(成分列[添字 * 4], 成分列[添字 * 4 + 1], 成分列[添字 * 4 + 2]).unwrap_or_else(|誤り| panic!("合成入力の色が値域を外れた: {誤り}"))
}

pub(super) fn ビュー空間の奥行きを作る(奥行き: メートル) -> ビュー空間の奥行き {
    ビュー空間の奥行き::生成する(奥行き).unwrap_or_else(|誤り| panic!("合成入力の奥行きが値域を外れた: {誤り}"))
}

fn 実数へ(値: u32) -> f32 {
    f32::from(u16::try_from(値).unwrap_or(u16::MAX))
}
