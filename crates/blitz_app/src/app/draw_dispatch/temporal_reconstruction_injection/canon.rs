//! 合成入力からCPU正本の再構成後の色を作り、GPUが書いた結果と突き合わせる工程。
//! 受け取るのは合成入力の材料と射影とGPUの読み戻し、返すのは差の要約である。
//!
//! 正本の合成の順を自分で並べ直さないのは、順そのものが方式の正本だからである。この工程は
//! `blitz_engine::temporal_reconstruction::一画素を再構成する`へ入力を渡すだけであり、採否・収め・混合の順を1つも知らない。

mod pixel;

use blitz_engine::temporal_reconstruction::{今のフレームの寄与率, 出現領域の相対許容, 線形色};
use blitz_render::HDR読み戻し画像;
use blitz_render::local_visibility::{射影の復元, 画像の寸法};

use super::synthesis::{区画の別, 合成入力の材料};

/// 突き合わせの結果。
pub(crate) struct 突き合わせの要約 {
    pub(crate) 全画素数: usize,
    /// 成分ごとの差の絶対値の最大。
    pub(crate) 最大の絶対差: f32,
    /// 正本の値で割った相対の差の最大。正本が0に近い成分は絶対差だけを見る。
    pub(crate) 最大の相対差: f32,
    /// 履歴を採る枝・出現領域の枝・画面の外の枝の画素数。3つとも0でないことが枝を網羅した根拠になる。
    pub(crate) 枝別の画素数: [usize; 3],
}

pub(super) fn 突き合わせる(
    材料: &合成入力の材料, 寸法: 画像の寸法, 射影: 射影の復元, gpu: &HDR読み戻し画像
) -> 突き合わせの要約 {
    let 今の奥行き = pixel::ビュー空間の奥行きを作る(射影.奥行きを復元する(材料.深度[0]));
    let 許容 = 出現領域の相対許容::既定();
    let 寄与率 = 今のフレームの寄与率::既定();
    let mut 要約 = 突き合わせの要約 {
        全画素数: 寸法.画素数(),
        最大の絶対差: 0.0,
        最大の相対差: 0.0,
        枝別の画素数: [0; 3],
    };
    for 縦 in 0..寸法.高さ() {
        for 横 in 0..寸法.幅() {
            let 添字 = 寸法.通し番号(横, 縦);
            let 正本 = pixel::一画素の正本(
                材料,
                寸法,
                横,
                縦,
                pixel::判定の材料 {
                    今の奥行き, 許容, 寄与率
                },
            );
            要約.枝別の画素数[枝の番号(材料, 添字)] += 1;
            差を取り込む(&mut 要約, 正本, gpu, 添字);
        }
    }
    要約
}

fn 枝の番号(材料: &合成入力の材料, 添字: usize) -> usize {
    match 材料.区画一覧[添字] {
        区画の別::履歴を採る => 0,
        区画の別::出現領域 => 1,
        区画の別::画面の外 => 2,
    }
}

fn 差を取り込む(要約: &mut 突き合わせの要約, 正本: 線形色, gpu: &HDR読み戻し画像, 添字: usize) {
    let 成分列 = gpu.成分列();
    for (位置, 正本の値) in 正本.成分().iter().enumerate() {
        let gpuの値 = 成分列[添字 * 4 + 位置];
        let 絶対差 = (gpuの値 - 正本の値).abs();
        要約.最大の絶対差 = 要約.最大の絶対差.max(絶対差);
        if *正本の値 > 0.0 {
            要約.最大の相対差 = 要約.最大の相対差.max(絶対差 / 正本の値);
        }
    }
}
