//! 合成深度を注入して局所可視度を読み戻し、CPU正本と突き合わせる工程。受け取るのはそのフレームの描画入力と
//! 視点、返すのはそのフレームが提示へ到達したかである。
//!
//! 同じ入力で2フレーム描くのは、静止した画面でGPU出力がバイト一致することをこの実行で示すためである。
//! 標本の回転がフレームで回っていれば2枚が食い違う。2枚を別々の実行で採ると、実行間の差(スワップチェーンの
//! 世代・カメラの浮動小数の積み上げ)が一致の判定へ混ざる。
//!
//! 深度の焼き上げに使う射影は、そのフレームがGPUの即時定数へ押し込む値そのものである。別に組み立てると、
//! 正本と写しの差に「与えた射影の違い」が混ざる。

use blitz_render::local_visibility::{合成深度を焼く, 局所可視度画像を焼く};
use blitz_render::{フレーム描画入力, 読み戻し結果};

use super::frame_reach::描画の到達;
use crate::app::frame::フレーム視点;
use crate::app::アプリ;
use crate::cli::起動モード;
use crate::error::起動エラー;
use crate::reports::local_visibility::{self, 合成深度の形};
use crate::smoke::スモークアクション;

impl アプリ {
    /// このフレームで検収を走らせる形。`--frames`の最終フレームだけを対象にするのは、それより前のフレームでは
    /// 大気と間接照明の焼き上げが進行中で、局所可視性補正と無関係な要因が画面に残っているためである。
    pub(in crate::app) fn 局所可視性を検収する形(&self, アクション: スモークアクション) -> Option<合成深度の形> {
        let 形 = self.読み戻し検収.局所可視性の検収の形?;
        let 起動モード::スモーク実行 { フレーム数 } = self.起動モード else {
            return None;
        };
        let 最終フレームか = self.現在フレーム + 1 == フレーム数 && アクション != スモークアクション::差し替え前ダンプ;
        最終フレームか.then_some(形)
    }

    pub(in crate::app) fn 局所可視度を検収する(
        &mut self,
        描画入力: フレーム描画入力<'_>,
        視点情報: &フレーム視点,
        形: 合成深度の形,
    ) -> Result<描画の到達, 起動エラー> {
        let 設定 = self.世界の描画構成.局所可視性の描画設定.補正の設定;
        let 射影 = 視点情報.射影の復元;
        let Some(レンダラー) = &mut self.レンダラー else {
            return Ok(描画の到達::届かなかった);
        };
        let 寸法 = レンダラー.画面の寸法().map_err(描画側の失敗へ写す)?;
        let 場面 = 形.場面を作る().map_err(描画側の失敗へ写す)?;
        let 深度 = 合成深度を焼く(場面, 寸法, 射影).map_err(描画側の失敗へ写す)?;
        レンダラー.合成深度を注入する(&深度)?;
        let Some(一枚目) = 読み戻す(レンダラー, 描画入力.clone(), 形)? else {
            return Ok(描画の到達::届かなかった);
        };
        let Some(二枚目) = 読み戻す(レンダラー, 描画入力, 形)? else {
            return Ok(描画の到達::届かなかった);
        };
        let 正本 = 局所可視度画像を焼く(&深度, 射影, 設定).map_err(描画側の失敗へ写す)?;
        local_visibility::寸法の一致を確かめる(正本.寸法(), &一枚目);
        local_visibility::報告する(形, &正本, &一枚目, &二枚目);
        Ok(描画の到達::提示した)
    }
}

/// 1フレーム描いて局所可視度を読み戻す。見送られたフレームは行に見送りとして残し、入口がその行で落とす。
fn 読み戻す(
    レンダラー: &mut blitz_render::レンダラー,
    描画入力: フレーム描画入力<'_>,
    形: 合成深度の形,
) -> Result<Option<blitz_render::局所可視度読み戻し画像>, 起動エラー> {
    match レンダラー.一フレーム描画して局所可視度を読み戻す(描画入力)? {
        読み戻し結果::読み戻した(画像) => Ok(Some(画像)),
        読み戻し結果::見送った(理由) => {
            local_visibility::見送りを報告する(形, &format!("{理由:?}"));
            Ok(None)
        }
    }
}

/// 局所可視性補正の入力の値域違反を描画側の失敗として運ぶ。形の寸法も画面の寸法も描画側が決めた値であり、
/// アプリ層に固有の失敗ではない。
fn 描画側の失敗へ写す(誤り: blitz_render::local_visibility::局所可視性エラー) -> 起動エラー {
    blitz_render::レンダラーエラー::from(誤り).into()
}
