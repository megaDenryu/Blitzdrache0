//! 時間再構成の観測が1回ぶんの読み戻しを実行する工程。受け取るのはアプリと描画入力と局面の名前、
//! 返すのは読み戻した画像である。見送られたフレームは行に残して`None`を返し、入口はその行で落とす。
//!
//! 独立した工程にするのは、観測が2種類の画像(圧縮前のHDRと今のフレームの色)を同じ扱いで読むためである。
//! 見送りの残し方を呼び出しごとに書くと、局面によって行の形が変わって入口が読めなくなる。

use blitz_render::{HDR読み戻し画像, フレーム描画入力, 読み戻し結果};

use crate::app::アプリ;
use crate::error::起動エラー;
use crate::reports::temporal_reconstruction;

pub(super) fn 圧縮前のhdrを読み戻す(
    アプリ: &mut アプリ,
    描画入力: フレーム描画入力<'_>,
    局面: &str,
) -> Result<Option<HDR読み戻し画像>, 起動エラー> {
    let Some(レンダラー) = &mut アプリ.レンダラー else {
        return Ok(None);
    };
    結果を開く(レンダラー.一フレーム描画して圧縮前のhdrを読み戻す(描画入力)?, 局面)
}

pub(super) fn 今のフレームの色を読み戻す(
    アプリ: &mut アプリ,
    描画入力: フレーム描画入力<'_>,
    局面: &str,
) -> Result<Option<HDR読み戻し画像>, 起動エラー> {
    let Some(レンダラー) = &mut アプリ.レンダラー else {
        return Ok(None);
    };
    結果を開く(レンダラー.一フレーム描画して今のフレームの色を読み戻す(描画入力)?, 局面)
}

/// 見送りは行に残して`None`を返す。入口はその行で落とす。
fn 結果を開く(結果: 読み戻し結果<HDR読み戻し画像>, 局面: &str) -> Result<Option<HDR読み戻し画像>, 起動エラー> {
    match 結果 {
        読み戻し結果::読み戻した(画像) => Ok(Some(画像)),
        読み戻し結果::見送った(理由) => {
            temporal_reconstruction::見送りを報告する(局面, &format!("{理由:?}"));
            Ok(None)
        }
    }
}
