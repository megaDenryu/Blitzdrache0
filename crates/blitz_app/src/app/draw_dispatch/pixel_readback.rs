//! 画素判定対象フレームの読み戻し結果をスモーク判定へ渡す。

use blitz_render::{フレーム描画入力, 読み戻し結果};

use crate::error::起動エラー;
use crate::smoke::{self, スモークアクション};

pub(super) fn 画素を判定する(
    レンダラー: &mut blitz_render::レンダラー,
    描画入力: フレーム描画入力,
    アクション: スモークアクション,
) -> Result<(), 起動エラー> {
    match レンダラー.一フレーム描画して読み戻す(描画入力)? {
        読み戻し結果::読み戻した(画像) => smoke::ピクセルを判定する(&画像, アクション),
        読み戻し結果::見送った(理由) => Err(起動エラー::ピクセル判定失敗(
            format!("判定対象フレームで描画が見送られた: {理由:?}"),
        )),
    }
}
