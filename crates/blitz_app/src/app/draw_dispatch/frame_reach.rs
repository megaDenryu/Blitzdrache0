//! そのフレームが提示へ到達したかどうか。焼き直しの鍵を確定してよいかの判断だけに使う。
//!
//! 真偽値でなく判別共用体にするのは、`true`が「描いた」なのか「見送った」なのかを呼び出し側が取り違えると、
//! 見送ったフレームの鍵を確定して古い画像を恒久的に残すという、絵にしか現れない欠陥になるためである。

/// 1フレームの描画がどこまで進んだか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(in crate::app) enum 描画の到達 {
    /// コマンドを記録して送信し、スワップチェーンへ提示した。生成パスはGPUへ届いている。
    提示した,
    /// レンダラー未生成・最小化中・スワップチェーン再構築中などで、このフレームの生成パスがGPUへ1本も届かなかった。
    届かなかった,
}
