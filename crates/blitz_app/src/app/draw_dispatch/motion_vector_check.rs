//! 動きベクトルを読み戻して要約を出す工程。受け取るのはそのフレームの描画入力、返すのはそのフレームが提示へ
//! 到達したかである。
//!
//! 最終フレームだけを対象にするのは、それより前のフレームでは大気と間接照明の焼き上げが進行中で、
//! この観測と無関係な要因が実行時間に混ざるためである。読み戻し自体はどのフレームでも成立する。
//!
//! 合成深度の注入も期待値の突き合わせも持たないのは、段3aの確認が「動きベクトルが書かれていること」だけを
//! 見るためである。解析導出との許容付きの比較は段3bの検収が持つ
//! (参照: `_doc/設計/時間再構成.md`「検収戦略(判断g)」)。

use blitz_render::{フレーム描画入力, 読み戻し結果};

use super::frame_reach::描画の到達;
use crate::app::アプリ;
use crate::cli::起動モード;
use crate::error::起動エラー;
use crate::reports::motion_vector;
use crate::smoke::スモークアクション;

impl アプリ {
    /// このフレームで動きベクトルを読み戻すか。`--report-motion-vector`を与えた`--frames`の最終フレームだけが対象である。
    pub(in crate::app) fn 動きベクトルを報告するフレームか(&self, アクション: スモークアクション) -> bool {
        if !self.読み戻し検収.動きベクトルを報告するか {
            return false;
        }
        let 起動モード::スモーク実行 { フレーム数 } = self.起動モード else {
            return false;
        };
        self.現在フレーム + 1 == フレーム数 && アクション != スモークアクション::差し替え前ダンプ
    }

    pub(in crate::app) fn 動きベクトルを報告する(
        &mut self, 描画入力: フレーム描画入力<'_>
    ) -> Result<描画の到達, 起動エラー> {
        let Some(レンダラー) = &mut self.レンダラー else {
            return Ok(描画の到達::届かなかった);
        };
        match レンダラー.一フレーム描画して動きベクトルを読み戻す(描画入力)? {
            読み戻し結果::読み戻した(画像) => {
                motion_vector::報告する(&画像);
                Ok(描画の到達::提示した)
            }
            読み戻し結果::見送った(理由) => {
                motion_vector::見送りを報告する(&format!("{理由:?}"));
                Ok(描画の到達::届かなかった)
            }
        }
    }
}
