//! 動きベクトルを読み戻して要約を出す工程。受け取るのはそのフレームの描画入力、返すのはそのフレームが提示へ
//! 到達したかである。
//!
//! どのフレームで読み戻すかは`検収の起動設定`の経路の判定が決める。読み戻し自体はどのフレームでも成立する。
//!
//! 合成深度の注入も期待値の突き合わせも持たないのは、段3aの確認が「動きベクトルが書かれていること」だけを
//! 見るためである。解析導出との許容付きの比較は段3bの検収が持つ
//! (参照: `_doc/設計/時間再構成.md`「検収戦略(判断g)」)。

use blitz_render::{フレーム描画入力, 読み戻し結果};

use super::frame_reach::描画の到達;
use crate::app::screen_installation::画面の据え付け;
use crate::app::アプリ;
use crate::error::起動エラー;
use crate::reports::motion_vector;

impl アプリ {
    pub(in crate::app) fn 動きベクトルを報告する(&mut self, 描画入力: フレーム描画入力<'_>) -> Result<描画の到達, 起動エラー> {
        let レンダラー = 画面の据え付け::描画の最中に借りる(&mut self.据え付け).レンダラーを借りる();
        match レンダラー.一フレーム描画して動きベクトルを読み戻す(描画入力)? {
            読み戻し結果::読み戻した(画像) => {
                motion_vector::報告する(&画像);
                Ok(描画の到達::提示した)
            }
            読み戻し結果::見送った(理由) => {
                motion_vector::見送りを報告する(&format!("{理由:?}"));
                Ok(描画の到達::届かなかった)
            }
        }
    }
}
