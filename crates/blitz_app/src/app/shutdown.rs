//! イベントループを閉じた後の局面。`main.rs`が呼ぶのは、起動時エラーの取り出し・検証カウンタの取得・据え付けの破棄の3つである。
//! 呼ばれるのはプロセスの終わりに各1回であり、毎フレームの描画とは呼び出し頻度も触れるフィールドも違う。
//!
//! 注意: 検証カウンタは据え付けの破棄より前に取得し、件数の読み取りは破棄の後に行う
//! (参照: `_doc/開発スレッド/開発スレッド_2026-07-20_M0実装.md`「判断3」)。

use blitz_render::検証カウンタ;

use super::screen_installation::画面の据え付け;
use super::アプリ;
use crate::error::起動エラー;

impl アプリ {
    /// resumed/window_event内で発生した起動時エラーを取り出す。
    pub(crate) fn 起動時エラーを取り出す(&mut self) -> Option<起動エラー> {
        self.起動時エラー.take()
    }

    /// 破棄後に読むための検証カウンタ。レンダラー未生成なら`None`(一度も描画していないため検証層のメッセージも発生し得ない)。
    pub(crate) fn 検証カウンタを取得する(&self) -> Option<検証カウンタ> {
        self.据え付け.as_ref().map(画面の据え付け::レンダラーを見る).map(blitz_render::レンダラー::検証カウンタを取得する)
    }

    /// イベントループ終了後に呼び、破棄順序を明示する。据え付けの中の破棄順はその型の宣言順が決める。
    pub(crate) fn 据え付けを破棄する(&mut self) {
        self.据え付け = None;
    }
}
