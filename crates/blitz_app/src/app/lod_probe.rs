//! 個体別LODの検収で使う、カメラを1フレームおきに前後させる探査。受け取るのは現在のフレーム番号、
//! 動かすのはカメラの注視点だけである。
//!
//! 段の境界をヒステリシス帯の内側でまたぐ往復を決定的に作るために置く。往復しても段が入れ替わらないことが
//! ヒステリシスの働きであり、それを実機で見るにはカメラが境界を挟んで前後する実行が要る。
//! 注視点を動かすとカメラの視点も同じだけ動くため、ヨー・ピッチ・距離を保ったまま既知量だけ視点を移せる。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「個体別LOD」

use blitz_engine::カメラ;
use blitz_math::メートル;

pub(super) struct 個体詳細段探査 {
    刻み: メートル,
    /// 現在カメラへ適用済みのずれ。目標との差だけを動かすため、フレームごとのずれが累積しない。
    適用済み: メートル,
}

impl 個体詳細段探査 {
    pub(super) fn 生成する(刻み: Option<メートル>) -> Option<Self> {
        刻み.map(|刻み| Self {
            刻み,
            適用済み: メートル::生成する(0.0),
        })
    }

    /// カメラ更新の直後、ストリーミングと可視判定より前に呼ぶ。奇数フレームで刻みぶん奥へ、偶数フレームで元へ戻す。
    pub(super) fn 適用する(&mut self, カメラ: &mut カメラ, 現在フレーム: u32) {
        let 目標 = if 現在フレーム % 2 == 1 {
            self.刻み
        } else {
            メートル::生成する(0.0)
        };
        let 差 = 目標 - self.適用済み;
        self.適用済み = 目標;
        カメラ.注視点をずらす(メートル::生成する(0.0), メートル::生成する(0.0), 差);
    }
}
