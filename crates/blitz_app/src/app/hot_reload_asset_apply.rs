//! 生成台帳で公開が完了した実行時カタログ・チャンク目録・起動時シーンを1組として反映する。
//! 触れるフィールドはゲーム配線・据え付け・描画束の台帳・ストリーミング・ホットリローダーに限る。

mod validation;

use super::draw_bundle_ledger::起動時シーンの差し替え材料;
use super::screen_installation::画面の据え付け;
use super::アプリ;
use crate::hot_reload::{公開済みの実行時アセット一式, 起動時シーンの更新};
use validation::反映前の検査を通す;

impl アプリ {
    pub(super) fn 公開済みの実行時アセット一式を反映する(&mut self, 一式: 公開済みの実行時アセット一式) {
        let Some(準備) = 反映前の検査を通す(&self.ストリーミング, &self.ゲーム配線, &一式) else {
            return;
        };
        // 層のタイルを先に据えるのは、以下のシーン変換とストリーミングがこの世代のタイルを引くためである。
        self.描画束の台帳.地表の層のタイルを据える(準備.地表の層のタイル);
        let レンダラー = 画面の据え付け::描画の最中に借りる(&mut self.据え付け).レンダラーを借りる();
        let 起動時シーンの内容 = match 一式.起動時シーン {
            起動時シーンの更新::同じ内容 { 内容 } => 内容,
            起動時シーンの更新::変更あり { 内容, シーン } => {
                let 差し替え材料 = 起動時シーンの差し替え材料 {
                    シーン: &シーン,
                    並べ方: self.描画対象の並べ方,
                    大域ずらし量: self.大域ずらし量,
                    チャンク一辺: 準備.一辺,
                    ゲーム配線: &self.ゲーム配線,
                };
                if let Err(誤り) = self.描画束の台帳.起動時シーンを差し替えて再登録する(レンダラー, 差し替え材料) {
                    eprintln!("[hot-reload] 起動時シーンを差し替えられなかった: {誤り}");
                    return;
                }
                内容
            }
        };
        if let Some(配線) = self.ストリーミング.配線を可変で借りる()
            && let Err(誤り) = 配線.チャンク目録と描画束を差し替える(一式.チャンク目録, レンダラー, &mut self.描画束の台帳)
        {
            eprintln!("[hot-reload] チャンク目録を差し替えられなかった: {誤り}");
            return;
        }
        self.ゲーム配線.高さ場を据える(準備.高さ場);
        self.ホットリローダー.実行時アセット一式を採用する(一式.カタログ, 起動時シーンの内容, 一式.公開完了印);
    }
}
