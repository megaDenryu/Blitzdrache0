//! 台帳のプリミティブ描画項目を、レンダラーが読む受け皿へ詰め直す走査。受け取るのは台帳と空にする受け皿、積むのは束ごと・描画対象ごとの発行である。
//!
//! 台帳から束IDの列を取り、束ごとに読み口で引き当てる。台帳の内側の器の並びをこの工程が知らないため、台帳が並べ方を変えても詰め直しは変わらない。
//! 束の中の項目は描画対象の並び順に連なっているため、そのまま順に積めば受け皿の区間が描画対象ごとに切れる。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「可視ID列の契約」

use blitz_engine::primitive_draw_item::プリミティブ描画項目;
use blitz_render::frame_input::{プリミティブ描画発行, プリミティブ発行受け皿};

use super::プリミティブ描画項目台帳;
use crate::error::起動エラー;

pub(super) fn 詰め直す(
    台帳: &プリミティブ描画項目台帳, 受け皿: &mut プリミティブ発行受け皿
) -> Result<(), 起動エラー> {
    受け皿.空にする();
    for 束id in 台帳.束id一覧() {
        let Some(一覧) = 台帳.束のプリミティブ描画項目(束id) else {
            continue;
        };
        for 項目 in 一覧.一覧() {
            受け皿.積む(束id, 項目.描画片().描画対象添字(), 発行へ写す(*項目)?);
        }
    }
    Ok(())
}

/// プリミティブ描画項目のインデックス区間と材質スロットを、GPUが受け取る幅の描画発行へ写す。狭められない値の拒否は生成側が持つ。
fn 発行へ写す(項目: プリミティブ描画項目) -> Result<プリミティブ描画発行, 起動エラー> {
    let 範囲 = 項目.描画範囲();
    let 発行 = プリミティブ描画発行::生成する(
        項目.描画片().詳細段番号(),
        範囲.インデックス開始(),
        範囲.インデックス数(),
        範囲.頂点基準(),
        項目.描画片().材質スロット().番号を返す(),
    )?;
    Ok(発行)
}
