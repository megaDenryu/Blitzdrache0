//! 提示画像の読み戻しと書き出しの工程。受け取るのはレンダラーと1フレームの描画入力とダンプ先、返すのは読み戻した提示画像である。
//!
//! 書き出す形式は`<ベース名>.raw`(RGBA8連結)と`<ベース名>.size`(幅 高さ)である。
//! 読み戻した画像を返すのは、代表画素の照合が検収の設定と天空とカメラを読み、この工程が触るものと重ならないためである。
//! 照合を呼ぶ順序は呼び出し元の振り分けが持つ。

use std::path::Path;

use blitz_render::{レンダラー, 読み戻し画像};

use super::寸法を書く;
use crate::error::起動エラー;

pub(super) fn 提示画像を読み戻して書き出す(レンダラー: &mut レンダラー, 描画入力: blitz_render::フレーム描画入力<'_>, ダンプ先: &Path) -> Result<読み戻し画像, 起動エラー> {
    match レンダラー.一フレーム描画して読み戻す(描画入力)? {
        blitz_render::読み戻し結果::読み戻した(画像) => {
            書き出す(&画像, ダンプ先)?;
            Ok(画像)
        }
        blitz_render::読み戻し結果::見送った(理由) => Err(起動エラー::フレームダンプ失敗(format!("ダンプ対象フレームで描画が見送られた: {理由:?}"))),
    }
}

fn 書き出す(画像: &読み戻し画像, ベース名: &Path) -> Result<(), 起動エラー> {
    let 幅 = 画像.幅();
    let 高さ = 画像.高さ();
    let mut バイト列 = Vec::with_capacity(usize::try_from(u64::from(幅) * u64::from(高さ) * 4).unwrap_or(0));
    for y in 0..高さ {
        for x in 0..幅 {
            let ピクセル = 画像.ピクセル(x, y).unwrap_or([0, 0, 0, 0]);
            バイト列.extend_from_slice(&ピクセル);
        }
    }

    let 提示画像のパス = ベース名.with_extension("raw");
    std::fs::write(&提示画像のパス, バイト列).map_err(|誤り| 起動エラー::フレームダンプ失敗(format!("{}: {誤り}", 提示画像のパス.display())))?;
    寸法を書く(幅, 高さ, ベース名)?;
    println!("[dump-frame] 書き出した: {}", 提示画像のパス.display());
    Ok(())
}
