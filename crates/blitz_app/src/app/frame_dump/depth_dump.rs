//! 最終深度の読み戻しと書き出しの工程。受け取るのはアプリと1フレームの描画入力とダンプ先、返すのはそのフレームが提示まで届いたかどうかである。
//!
//! 書き出す形式は`<ベース名>.depth32`(単精度リトルエンディアン連結、行優先、1画素1要素)と`<ベース名>.size`(幅 高さ)である。
//! 深度プリパスの三条件が同じ深度を作ったかどうかは、この並びのバイト一致で判定する
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「IIaの実装設計」)。
//!
//! 代表画素の照合を呼ばないのは、深度に対する期待値をこの工程が1つも持たないためである。

use std::path::Path;

use blitz_render::深度読み戻し画像;

use super::super::draw_dispatch::描画の到達;
use super::super::アプリ;
use super::寸法を書く;
use crate::error::起動エラー;

pub(super) fn 読み戻して書き出す(
    アプリ: &mut アプリ,
    描画入力: blitz_render::フレーム描画入力<'_>,
    ダンプ先: &Path,
) -> Result<描画の到達, 起動エラー> {
    let Some(レンダラー) = &mut アプリ.レンダラー else {
        return Ok(描画の到達::届かなかった);
    };
    match レンダラー.一フレーム描画して最終深度を読み戻す(描画入力)? {
        blitz_render::読み戻し結果::読み戻した(画像) => {
            書き出す(&画像, ダンプ先)?;
            Ok(描画の到達::提示した)
        }
        blitz_render::読み戻し結果::見送った(理由) => Err(起動エラー::フレームダンプ失敗(format!(
            "ダンプ対象フレームで描画が見送られた: {理由:?}"
        ))),
    }
}

fn 書き出す(画像: &深度読み戻し画像, ベース名: &Path) -> Result<(), 起動エラー> {
    let 深度列 = 画像.深度列();
    let mut バイト列 = Vec::with_capacity(深度列.len() * 4);
    for 深度 in 深度列.iter().copied() {
        バイト列.extend_from_slice(&深度.to_le_bytes());
    }

    let 深度パス = ベース名.with_extension("depth32");
    std::fs::write(&深度パス, バイト列).map_err(|誤り| 起動エラー::フレームダンプ失敗(format!("{}: {誤り}", 深度パス.display())))?;
    寸法を書く(画像.幅(), 画像.高さ(), ベース名)?;
    println!("[dump-depth-frame] 書き出した: {}", 深度パス.display());
    Ok(())
}
