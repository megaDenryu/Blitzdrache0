//! `--report-cluster-assignment`が指定された実行で、クラスタの選別が書いた割り当てを読み戻して統計を1行で出す工程。
//! 受け取るのはアプリとそのフレームの視点、返すものは無い。
//!
//! ダンプ対象フレームの後に呼ぶのは、そのフレームの描画が終わっていなければ選別の書き込みが済んでいないためである。
//! 読み戻しはGPUの全作業完了を待つため、この経路が通るのは検収の実行だけである。

use super::super::frame::フレーム視点;
use super::super::アプリ;

pub(super) fn 報告する(アプリ: &アプリ, 視点情報: &フレーム視点) {
    if !アプリ.読み戻し検収.クラスタ選別の割り当てを報告するか {
        return;
    }
    let Some(レンダラー) = &アプリ.レンダラー else {
        crate::reports::cluster_assignment::読み戻せなかったことを告げる("レンダラーがまだ生成されていない");
        return;
    };
    let 視点 = 描画視点へ写す(視点情報);
    let ライティング = アプリ.天空.ライティング();
    match レンダラー.クラスタ選別の割り当て統計を読み戻す(&視点, &ライティング.局所光源列()) {
        Ok(統計) => crate::reports::cluster_assignment::報告する(統計),
        Err(誤り) => crate::reports::cluster_assignment::読み戻せなかったことを告げる(&誤り.to_string()),
    }
}

/// そのフレームの描画入力が組み立てたのと同じ描画視点を組み直す。カメラ大域原点をカメラの大域位置に置く規約も同じである。
fn 描画視点へ写す(視点情報: &フレーム視点) -> blitz_render::描画視点 {
    blitz_render::描画視点::生成する(
        視点情報.ビュー射影の組,
        視点情報.カメラ相対ビュー変換,
        視点情報.カメラ大域位置,
        視点情報.カメラ大域位置,
        視点情報.射影の復元,
    )
}
