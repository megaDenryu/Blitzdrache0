//! `--indirect-probe`が指定された実行で、読み戻し画像の板の代表画素と注入した解析入力を照合する工程。
//! 受け取るのは検収条件と天空状態と読み戻し画像とそのフレームの視点と大域ずらし量、返すのは無しであり、結果は板ごとの1行として出す。
//!
//! 空の代表画素の照合と分けるのは、読むものが違うためである。あちらは大気の再現条件から空の色を組み直し、
//! こちらは注入した解析入力から表面の間接光を組み直す。

use blitz_engine::sky::天空状態;
use blitz_math::大域ワールド位置;
use blitz_render::読み戻し画像;

use super::super::frame::フレーム視点;
use crate::reports::indirect_probe::遠方環境の検収条件;

/// `--indirect-probe`が指定されていなければ何もしない。空の方針を持たない世界では太陽方向が決まらないため、
/// 照合の材料が無い旨を1行だけ出す。
pub(super) fn 間接照明代表板を照合する(検収条件: Option<遠方環境の検収条件>, 天空状態: Option<&天空状態>, 画像: &読み戻し画像, 視点情報: &フレーム視点, 大域ずらし量: 大域ワールド位置) {
    let Some(条件) = 検収条件 else {
        return;
    };
    let Some(天空状態) = 天空状態 else {
        println!("間接照明代表板 照合できなかった 理由=このフレーム構成に天空状態が無い");
        return;
    };
    crate::reports::indirect_probe::代表板を照合する(&crate::reports::indirect_probe::照合の材料 {
        条件,
        画像,
        視点情報,
        大域ずらし量,
        太陽方向: 天空状態.太陽方向().成分(),
    });
}
