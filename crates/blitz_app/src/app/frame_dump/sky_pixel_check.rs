//! `--report-sky-pixel`が指定された実行で、読み戻し画像の代表画素と天空の再現条件を照合する工程。
//! 受け取るのはアプリと読み戻し画像とそのフレームの視点、返すのは無しであり、結果は1行の報告として出す。
//!
//! 書き出しの工程と分けるのは、触れるものが違うためである。この工程が読むのは天空と代表画素の指定であり、
//! ダンプ先のパスにもファイル書き出しにも触れない。

use blitz_render::読み戻し画像;

use super::super::frame::フレーム視点;
use super::super::アプリ;

/// `--report-sky-pixel`が指定されていなければ何もしない。空を持たない世界や大気のベイク済み画像資源を持たない
/// フレーム構成では、指定があっても照合の材料が無い旨を1行だけ出す。
pub(super) fn 照合する(アプリ: &アプリ, 画像: &読み戻し画像, 視点情報: &フレーム視点) {
    if アプリ.読み戻し検収.空の代表画素.is_empty() {
        return;
    }
    let Some(条件) = アプリ.天空.再現条件() else {
        println!("空代表画素 照合できなかった 理由=このフレーム構成に大気のベイク済み画像の材料が無い");
        return;
    };
    // 空パスが読むのはずらし付きであるため、その画素を照合するこちらも同じ1本の逆をたどる。
    let 逆ビュー射影行列 = 視点情報.ビュー射影の組.ずらし付き().逆変換する().gpu境界用列優先配列();
    crate::reports::sky_pixel::代表画素を照合する(&crate::reports::sky_pixel::照合の材料 {
        条件,
        画像,
        逆ビュー射影行列,
        // カメラ相対フレームの原点はこのフレームのカメラ自身の大域位置に置く(`frame::視点を求める`参照)ため、
        // カメラのカメラ相対位置は常に原点である。
        カメラ相対位置: [0.0, 0.0, 0.0],
        画素一覧: &アプリ.読み戻し検収.空の代表画素,
    });
}
