//! そのフレームの読み戻しをどのファイル名で書き出すかを決める工程。受け取るのはアプリと基準名とスモークの動作、
//! 返すのは書き出し先のパスである。
//!
//! 名前の付け方を1つの工程へ集めるのは、後置きを足す条件が3つあり(段差の走査・差し替え前・先行フレーム)、
//! 呼び出し側がそのどれかを取りこぼすと、2枚の絵が同じ名前へ重なって片方が消えるためである。

use std::path::{Path, PathBuf};

use super::super::アプリ;
use crate::cli::起動モード;
use crate::smoke::スモークアクション;

/// 差し替え前のフレームへ足す後置き。
const 差し替え前の後置き: &str = "_before";
/// 同一起動内の再現性を見るために撮る、最終フレームの1つ前へ足す後置き。
const 先行フレームの後置き: &str = "_preceding";

pub(super) fn 決める(アプリ: &アプリ, 基準名: &Path, アクション: スモークアクション) -> PathBuf {
    if let Some(撮影) = アプリ.天空.このフレームの撮影(アプリ.現在フレーム) {
        return 後置きを足す(基準名, 撮影.ファイル名の後置き().as_str());
    }
    if let 起動モード::スモーク実行 { フレーム数 } = アプリ.起動モード
        && アプリ.先行ダンプのフレームか(フレーム数)
    {
        return 後置きを足す(基準名, 先行フレームの後置き);
    }
    if アクション == スモークアクション::差し替え前ダンプ {
        return 後置きを足す(基準名, 差し替え前の後置き);
    }
    基準名.to_path_buf()
}

/// 拡張子の付け方は最終フレームと同じにする。同じ実行の複数枚を検収側が同じ読み手で読めるようにするためである。
fn 後置きを足す(基準: &Path, 後置き: &str) -> PathBuf {
    let 名前 = 基準
        .file_name()
        .map_or_else(|| "frame".to_string(), |名前| 名前.to_string_lossy().into_owned());
    基準.with_file_name(format!("{名前}{後置き}"))
}
