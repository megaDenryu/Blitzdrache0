//! チャンクストリーミングの配線。CLIの起動設定から調停を組み立て、毎フレーム、カメラが確定した後のプレイヤー位置を渡して進める。
//! 判断も計算もエンジン側の`ストリーミング調停`が持ち、ここは組み立てと呼び出しと報告の有無だけを扱う。

mod bundle_sync;
mod measurement;
mod route;

use std::time::Instant;

use blitz_engine::{ストリーミングメモリ量, ストリーミング調停, ストリーミング調停設定};

use super::アプリ;
use crate::cli::{ストリーミング起動設定, 起動モード};
use crate::error::起動エラー;

pub(crate) use measurement::ストリーミング要約;

/// チャンク1辺の大域メートル。検証用世界の格子寸法に合わせる。描画束のアンカー導出も同じ値を使う。
pub(super) const 一辺メートル: f64 = 100.0;

/// 先読み半径。検証用世界は5×5であり、中心と周囲8チャンクを必要集合にする。
const 先読み半径: u8 = 1;

pub(super) struct ストリーミング配線 {
    調停: ストリーミング調停,
    位置決定: route::プレイヤー位置決定,
    計測: measurement::ストリーミング計測,
    上限: ストリーミングメモリ量,
    報告する: bool,
    /// 実破棄済み束IDの受け皿。毎フレーム使い回し、破棄バッチごとのヒープ再確保を避ける。
    実破棄受け皿: Vec<blitz_render::描画束ID>,
}

/// `--streaming`が無ければ`None`を返す。既存のスモークとベンチはチャンク世界を使わないため、既定では読込器のスレッドも起動しない。
pub(super) fn 構築する(
    起動設定: &ストリーミング起動設定,
    モード: 起動モード,
    アセットルート: &std::path::Path,
) -> Result<Option<ストリーミング配線>, 起動エラー> {
    if !起動設定.有効 {
        return Ok(None);
    }
    let 目録 = super::scene_load::チャンク目録を構築する(アセットルート)?;
    let 設定 = ストリーミング調停設定 {
        一辺: blitz_math::大域メートル::生成する(一辺メートル),
        先読み半径,
        上限: 起動設定.上限,
    };
    Ok(Some(ストリーミング配線 {
        調停: ストリーミング調停::起動する(設定, 目録)?,
        位置決定: route::プレイヤー位置決定::構築する(起動設定.位置源)?,
        計測: measurement::ストリーミング計測::生成する(モード),
        上限: 起動設定.上限,
        報告する: 起動設定.報告する,
        実破棄受け皿: Vec::new(),
    }))
}

impl ストリーミング配線 {
    /// 見送りフレーム数はレンダラーの計器であり配線は保持しないため、呼出し側が渡す。
    pub(super) fn 要約を作る(&self, 見送りフレーム数: u64) -> ストリーミング要約 {
        self.計測.要約を作る(self.調停.転送量(), self.上限, 見送りフレーム数)
    }

    /// レンダラーのシーン差し替えに続けて呼ぶ。差し替えは描画資源を作り直してチャンクの描画束を全部消すため、
    /// 何を捨てて何を残すかは調停のリセットが持ち、ここは呼び出しだけを行う。
    pub(super) fn 調停をリセットする(&mut self) {
        self.調停.リセットする();
    }
}

impl アプリ {
    /// カメラ更新の直後に呼ぶ。既定の位置源はカメラの視点位置であり、必要集合の中心を確定した視点から決めるため、カメラより先に呼んではならない。
    pub(super) fn ストリーミングを進める(&mut self) -> Result<(), 起動エラー> {
        let 大域オフセット = self.大域オフセット;
        let Some(配線) = &mut self.ストリーミング else {
            return Ok(());
        };
        // レンダラーが揃う前は進めない。準備完了したCPUデータを載せる相手が居らず、調停の保管だけが増えるためである。
        let Some(レンダラー) = &mut self.レンダラー else {
            return Ok(());
        };
        let Some(カタログ) = self.ホットリローダー.カタログを参照する() else {
            return Err(起動エラー::ストリーミングカタログ未構築);
        };
        // 格子と必要集合はオフセットを加えない世界座標で決まるため、位置源へは大域オフセットを足さない。オフセットは描画アンカーとカメラだけへ効く。
        let 大域位置 = 配線.位置決定.位置を求める(self.現在フレーム, &self.カメラ);
        // 計測区間は調停と描画束の追加解除の両方を含む。ストリーミングがメインスレッドを占める時間はこの合計である。
        let 開始 = Instant::now();
        let 進行 = 配線.調停.一フレーム進める(大域位置, カタログ)?;
        bundle_sync::適用する(&mut 配線.調停, レンダラー, &進行, &mut 配線.実破棄受け皿, 大域オフセット)?;
        配線.計測.記録する(self.現在フレーム, 開始.elapsed(), &進行);
        if 配線.報告する {
            crate::reports::streaming::進行を表示する(self.現在フレーム, &進行);
        }
        Ok(())
    }
}
