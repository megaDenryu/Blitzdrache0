//! CLI起動設定からアプリの初期状態を構築する。

use super::scene_camera::シーン初期カメラを作る;
use super::{frame_timing, streaming, アプリ};
use crate::cli::起動設定;
use crate::error::起動エラー;
use crate::hot_reload::ホットリローダー;
use crate::input::入力状態;
use blitz_render::クリアカラー;

impl アプリ {
    /// チャンク目録の読込と読込ワーカーの起動を伴い失敗しうるため、結果を返す。
    pub(crate) fn 生成する(起動設定: 起動設定, クリア色: クリアカラー) -> Result<Self, 起動エラー> {
        let 大域ずらし量 = 起動設定.平行移動.大域ずらし量;
        let フレーム間隔計測 = 起動設定
            .フレーム時間報告
            .then(|| frame_timing::フレーム間隔計測::生成する(起動設定.モード));
        let シーン基準ライティング = super::scene_lighting::シーン初期ライティングを作る(
            &起動設定.シーン名,
            起動設定.ライティング有効,
            大域ずらし量,
            &起動設定.シャドウ計測,
        );
        let 天空 = super::time_of_day::天空配線::生成する(&起動設定.シーン名, &起動設定.時間帯, シーン基準ライティング);
        let フレーム構成 = blitz_engine::既定フレーム構成を作る(起動設定.ポスト処理有効, 天空.空を描くか());
        let 報告要求 = super::report_requests::報告要求::起動設定から作る(&起動設定);
        let ストリーミング = streaming::構築する(&起動設定.ストリーミング, 起動設定.モード, &起動設定.アセットルート)?;
        Ok(Self {
            レンダラー: None,
            window: None,
            起動モード: 起動設定.モード,
            ホットリローダー: ホットリローダー::生成する(起動設定.シェーダー監視パス.clone()),
            シェーダー監視パス: 起動設定.シェーダー監視パス,
            カメラ: シーン初期カメラを作る(&起動設定.シーン名, &起動設定.平行移動),
            シーン名: 起動設定.シーン名,
            アセットルート: 起動設定.アセットルート,
            大域ずらし量,
            描画対象の並べ方: 起動設定.描画対象の並べ方,
            入力状態: 入力状態::生成する(),
            現在フレーム: 0,
            クリア色,
            天空,
            フレーム構成,
            空中遠近合成: 起動設定.時間帯.空中遠近合成,
            粒子表示: 起動設定.粒子表示,
            報告要求,
            フレーム間隔計測,
            開発ui: None,
            開発ui初期有効: 起動設定.開発ui初期有効,
            計測つまみ: super::frame::描画の計測つまみ::起動設定から作る(起動設定.画素診断, 起動設定.影キャスター全体有効),
            フレームダンプ先: 起動設定.フレームダンプ先,
            空の代表画素報告: 起動設定.空の代表画素報告,
            露出: 起動設定.露出,
            ブレンド: 起動設定.ブレンド,
            布モード: 起動設定.布モード,
            布プリセット: None,
            掴み中だった: false,
            アニメーション: None,
            アニメ時刻秒: 0.0,
            スモーク基準画像: None,
            ウィンドウ再構築検証有効: 起動設定.ウィンドウ再構築検証有効,
            ストリーミング,
            可視判定: super::visibility::可視判定配線::生成する(super::visibility::選別のつまみ {
                可視判定有効: 起動設定.インスタンス可視判定有効,
                段選択有効: 起動設定.インスタンス段選択有効,
                影キャスター有効: 起動設定.インスタンス影キャスター有効,
                キャスター距離分布を数える: 起動設定.キャスター距離分布報告,
                影の視距離: 起動設定.シャドウ計測.影の視距離,
            }),
            プリミティブ描画項目台帳: super::primitive_draw_item_registry::プリミティブ描画項目台帳::default(),
            可視個体の選別の計測: 起動設定
                .インスタンス区間報告
                .then(|| super::section_timing::区間計測::生成する(起動設定.モード)),
            個体詳細段探査: super::lod_probe::個体詳細段探査::生成する(起動設定.個体詳細段探査刻み),
            シーン読込計数: super::scene_read_count::シーン読込計数::default(),
            起動時エラー: None,
        })
    }
}
