//! CLI起動設定からアプリの初期状態を構築する。

use super::scene_camera::シーン初期カメラを作る;
use super::{frame_timing, streaming, アプリ};
use crate::cli::起動設定;
use crate::error::起動エラー;
use crate::hot_reload::ホットリローダー;
use crate::input::入力状態;
use blitz_render::クリアカラー;

impl アプリ {
    /// チャンク目録の読込と読込ワーカーの起動を伴い失敗しうるため、結果を返す。
    pub(crate) fn 生成する(起動設定: 起動設定, クリア色: クリアカラー) -> Result<Self, 起動エラー> {
        let 大域オフセット = 起動設定.平行移動.大域オフセット;
        let フレーム間隔計測 = 起動設定
            .フレーム時間報告
            .then(|| frame_timing::フレーム間隔計測::生成する(起動設定.モード));
        let 空方針 = super::time_of_day::世界の空方針を決める(&起動設定.シーン名, 起動設定.時間帯.空);
        let 空を描く = super::time_of_day::空を描くか(空方針, 起動設定.時間帯.空);
        let フレーム構成 = blitz_engine::既定フレーム構成を作る(起動設定.ポスト処理有効, 空を描く);
        let 空 = 空を描く.then(|| super::time_of_day::既定時刻の空入力を作る(空方針)).flatten();
        let ストリーミング = streaming::構築する(&起動設定.ストリーミング, 起動設定.モード, &起動設定.アセットルート)?;
        let ライティング =
            super::scene_lighting::シーン初期ライティングを作る(&起動設定.シーン名, 起動設定.ライティング有効, 大域オフセット);
        Ok(Self {
            レンダラー: None,
            window: None,
            起動モード: 起動設定.モード,
            ホットリローダー: ホットリローダー::生成する(起動設定.シェーダー監視パス.clone()),
            シェーダー監視パス: 起動設定.シェーダー監視パス,
            カメラ: シーン初期カメラを作る(&起動設定.シーン名, 起動設定.平行移動.カメラずれ, 起動設定.平行移動.カメラ俯角差分),
            シーン名: 起動設定.シーン名,
            アセットルート: 起動設定.アセットルート,
            大域オフセット,
            描画対象数: 起動設定.描画対象数,
            入力状態: 入力状態::生成する(),
            現在フレーム: 0,
            クリア色,
            ライティング,
            空,
            フレーム構成,
            粒子表示: 起動設定.粒子表示,
            gpu時間報告: 起動設定.gpu時間報告,
            gpuメモリ報告: 起動設定.gpuメモリ報告,
            描画発行報告: 起動設定.描画発行報告,
            フレーム間隔計測,
            実表示時間報告: 起動設定.実表示時間報告,
            開発ui: None,
            開発ui初期有効: 起動設定.開発ui初期有効,
            フレームダンプ先: 起動設定.フレームダンプ先,
            露出: 起動設定.露出,
            ブレンド: 起動設定.ブレンド,
            布モード: 起動設定.布モード,
            布プリセット: None,
            掴み中だった: false,
            アニメーション: None,
            アニメ時刻秒: 0.0,
            スモーク基準画像: None,
            ウィンドウ再構築検証有効: 起動設定.ウィンドウ再構築検証有効,
            ストリーミング,
            ストリーミング要約報告: 起動設定.ストリーミング.要約を報告する,
            可視判定: super::visibility::可視判定配線::生成する(起動設定.インスタンス可視判定有効, 起動設定.インスタンス段選択有効),
            群選択計測: 起動設定
                .インスタンス区間報告
                .then(|| super::section_timing::区間計測::生成する(起動設定.モード)),
            個体詳細段探査: super::lod_probe::個体詳細段探査::生成する(起動設定.個体詳細段探査刻み),
            シーン読込計数: super::scene_read_count::シーン読込計数::default(),
            起動時エラー: None,
        })
    }
}
