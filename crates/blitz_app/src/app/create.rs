//! CLI起動設定からアプリの初期状態を構築する。世界の描画の組み立て方の決定だけは`world_composition`が持つ。

mod world_composition;

pub(in crate::app) use world_composition::世界の描画構成;

use super::scene_camera::シーン初期カメラを作る;
use super::{frame_timing, streaming, アプリ};
use crate::cli::起動設定;
use crate::error::起動エラー;
use crate::hot_reload::ホットリローダー;
use crate::input::{カメラ操作の適用方針, 入力状態};
use blitz_render::クリアカラー;

impl アプリ {
    /// チャンク目録の読込と読込ワーカーの起動を伴い失敗しうるため、結果を返す。
    pub(crate) fn 生成する(起動設定: 起動設定, クリア色: クリアカラー) -> Result<Self, 起動エラー> {
        let 大域ずらし量 = 起動設定.平行移動.大域ずらし量;
        let フレーム間隔計測 = 起動設定
            .フレーム時間報告
            .then(|| frame_timing::フレーム間隔計測::生成する(起動設定.モード));
        let シーン基準ライティング = super::scene_lighting::シーン初期ライティングを作る(
            &起動設定.シーン,
            起動設定.ライティング.有効,
            大域ずらし量,
            &起動設定.シャドウ計測,
            起動設定.ライティング.局所光の件数,
            起動設定.ライティング.影を落とす灯の件数,
        )?;
        let mut 天空 = super::time_of_day::天空配線::生成する(super::time_of_day::生成材料 {
            種別: 起動設定.シーン.種別(),
            時間帯: &起動設定.時間帯,
            起動モード: 起動設定.モード,
            基準ライティング: シーン基準ライティング,
            明示境界を使わない: 起動設定.シャドウ計測.明示境界を使わない,
        })?;
        天空.段差走査を組む(起動設定.モード)?;
        let 世界の描画構成 = world_composition::決める(&起動設定, 天空.空を描くか())?;
        let 報告要求 = super::report_requests::報告要求::起動設定から作る(&起動設定);
        let ストリーミング = streaming::構築する(&起動設定.ストリーミング, 起動設定.モード, &起動設定.アセットの置き場)?;
        let スモーク実行 = crate::smoke::スモーク実行::起動設定から作る(&起動設定);
        Ok(Self {
            レンダラー: None,
            window: None,
            起動モード: 起動設定.モード,
            ホットリローダー: ホットリローダー::生成する(&起動設定.シェーダーの入口ファイル),
            カメラ: シーン初期カメラを作る(起動設定.シーン.種別(), &起動設定.平行移動),
            シーン: 起動設定.シーン,
            アセットの置き場: 起動設定.アセットの置き場,
            大域ずらし量,
            描画対象の並べ方: 起動設定.描画対象の並べ方,
            入力状態: 入力状態::生成する(カメラ操作の適用方針::起動モードから決める(起動設定.モード)),
            ゲーム配線: crate::game::ゲーム配線::起動設定から作る(起動設定.遊ぶゲーム, 起動設定.モード),
            現在フレーム: 0,
            視点の履歴: super::frame::視点の履歴::記録なしで生成する(),
            時間再構成の観測: super::draw_dispatch::時間再構成の観測::記録なしで生成する(),
            クリア色,
            天空,
            世界の描画構成,
            空中遠近合成: 起動設定.時間帯.空中遠近合成,
            粒子表示: 起動設定.粒子表示,
            報告要求,
            フレーム間隔計測,
            画面へ重ねるui: None,
            開発ui初期有効: 起動設定.開発ui初期有効,
            計測つまみ: super::frame::描画の計測つまみ::起動設定から作る(起動設定.画素診断, 起動設定.影キャスター全体有効),
            フレームダンプ先: 起動設定.フレームダンプ先,
            読み戻し検収: 起動設定.読み戻し検収,
            露出: 起動設定.露出,
            ブレンド: 起動設定.ブレンド,
            布モード: 起動設定.布モード,
            布プリセット: None,
            掴み中だった: false,
            アニメーション: None,
            アニメ時刻: blitz_math::秒::生成する(0.0),
            スモーク基準画像: None,
            ストリーミング,
            可視判定: super::visibility::可視判定配線::生成する(super::visibility::選別のつまみ {
                可視判定有効: 起動設定.インスタンス可視判定有効,
                段選択有効: 起動設定.インスタンス段選択有効,
                影キャスター有効: 起動設定.インスタンス影キャスター有効,
                キャスター距離分布を数える: 起動設定.キャスター距離分布報告,
                影の視距離: 起動設定.シャドウ計測.影の視距離,
            }),
            プリミティブ描画項目台帳: super::primitive_draw_item_registry::プリミティブ描画項目台帳::default(),
            永続束: super::persistent_bundles::永続束の状態::生成する(起動設定.遠景影キャスター有効),
            可視個体の選別の計測: 起動設定
                .インスタンス区間報告
                .then(|| super::section_timing::区間計測::生成する(起動設定.モード)),
            個体詳細段探査: super::lod_probe::個体詳細段探査::生成する(起動設定.個体詳細段探査刻み),
            シーン読込計数: super::scene_read_count::シーン読込計数::default(),
            スモーク実行,
            起動時エラー: None,
        })
    }
}
