//! アプリのストリーミング配線から、その描画の読込済みチャンクの形の出どころを組む工程。受け取るのはストリーミング配線の有無、
//! 返すのは出どころの枝である。刻みを回す工程とカメラの遮蔽の工程が同じ組み方を共有する。

use super::super::streaming::ストリーミング配線;
use crate::game::読込済みチャンクの形の出どころ;

pub(super) fn 読込済みチャンクの形の出どころを組む(
    ストリーミング: &Option<ストリーミング配線>,
) -> 読込済みチャンクの形の出どころ<'_> {
    match ストリーミング {
        None => 読込済みチャンクの形の出どころ::ストリーミングを使わない起動,
        Some(配線) => 読込済みチャンクの形の出どころ::ストリーミング調停(配線.調停()),
    }
}
