//! この描画のカメラ姿勢を確定する工程。受け取るのはそのフレームのカメラの操作意図とこの描画の時間の進み、返すのは無しである。
//! 触れるのは`視点`と`自己操作`と`世界実行`と、表示距離を決める工程(`camera_occlusion`)が借りるものである。
//!
//! いつ呼ばれるか: 1描画に1度、固定刻みを進めた後・ストリーミングの進行より前である。ストリーミングより前に置くのは、
//! 必要チャンク集合の中心を確定した視点位置から決めるためである。
//! ゲームの追従を先に据えてからカメラ操作を通すのは、そのフレームのマウス操作を追従後の注視点に対して効かせるためである。
//! 据える位置が刻み境界の確定値でなく混ぜた値なのは、注視点が描画機会ごとの時間意味に属するためである
//! (参照: `_doc/設計/時間の規律.md`「判断5」「判断6」)。混ぜた注視点はヨーへ回り込まないため、次のゲーム更新が
//! 前へ進む向きとして読む値は補間の影響を1つも受けない。
//! 表示距離を最後に決めるのは、注視点と理想距離がこの描画の値に揃った後の遮蔽を見るためである。

use blitz_engine::カメラの操作意図;

use super::super::time_step::この描画の時間の進み;
use super::super::アプリ;
use crate::error::起動エラー;

impl アプリ {
    pub(super) fn カメラをこの描画の視点へ更新する(&mut self, 意図: カメラの操作意図, 時間の進み: &この描画の時間の進み) -> Result<(), 起動エラー> {
        let 注視点 = self.世界実行.カメラの注視点にする混ぜた大域位置(時間の進み.補間の割合());
        self.視点.注視点へ追従する(注視点, self.大域ずらし量);
        self.視点.この描画の視点へ更新する(意図);
        self.自己操作.探査をカメラへ適用する(self.視点.カメラを可変で借りる(), 時間の進み.描画機会の番号());
        self.世界を描画機会の時間意味で更新して表示距離を決める(時間の進み)
    }
}
