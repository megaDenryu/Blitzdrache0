//! この描画のカメラ姿勢を確定する工程。受け取るのはそのフレームのカメラインテントとこの描画の時間の進み、返すのは無しである。
//! 触れるのは`カメラ`と`個体詳細段探査`と、表示距離を決める工程(`camera_occlusion`)が借りるものである。
//!
//! いつ呼ばれるか: 1描画に1度、固定刻みを進めた後・ストリーミングの進行より前である。ストリーミングより前に置くのは、
//! 必要チャンク集合の中心を確定した視点位置から決めるためである。
//! ゲームの追従を先に据えてからカメラ操作を通すのは、そのフレームのマウス操作を追従後の注視点に対して効かせるためである。
//! 表示距離を最後に決めるのは、注視点と理想距離がこの描画の値に揃った後の遮蔽を見るためである。

use blitz_engine::カメラインテント;

use super::super::time_step::この描画の時間の進み;
use super::super::アプリ;
use crate::error::起動エラー;

impl アプリ {
    pub(super) fn カメラをこの描画の視点へ更新する(
        &mut self,
        インテント: カメラインテント,
        時間の進み: &この描画の時間の進み,
    ) -> Result<(), 起動エラー> {
        self.ゲームが供給する位置へ注視点を移す(時間の進み.補間の割合());
        self.カメラ.更新する(インテント);
        if let Some(探査) = &mut self.個体詳細段探査 {
            探査.適用する(&mut self.カメラ, self.現在フレーム);
        }
        self.カメラの表示距離をこの描画の遮蔽で決める(時間の進み.刻み数())
    }
}
