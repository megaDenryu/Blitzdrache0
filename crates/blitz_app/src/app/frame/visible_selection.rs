//! この描画で描く個体を選び、選別に費やした時間を計測する工程。受け取るのはそのフレームの視点、
//! 返すのは選別の失敗である。触れるのは`可視判定`と`可視個体の選別の計測`だけである。
//!
//! いつ呼ばれるか: 1描画に1度、視点を求めた後・描画の発行より前である。
//! 可視判定がずらし無しのビュー射影を読むのは、1画素未満の揺れで視錐台の境界の対象が出入りすると、
//! 描画対象の集合がフレームごとに変わるためである。
//! 計測が無効な実行では時刻を1度も読まない。読むと既存の性能時系列の条件が指定なしで変わる。

use super::super::アプリ;
use super::フレーム視点;
use crate::error::起動エラー;

impl アプリ {
    pub(super) fn この描画の可視個体を選別する(&mut self, 視点情報: &フレーム視点) -> Result<(), 起動エラー> {
        let 開始 = self.可視個体の選別の計測.as_ref().map(|_| std::time::Instant::now());
        let 結果 = self
            .可視判定
            .判定する(視点情報.ビュー射影の組.ずらし無し(), self.天空.ライティング(), 視点情報.カメラ大域位置);
        if let (Some(開始), Some(計測)) = (開始, &mut self.可視個体の選別の計測) {
            計測.記録する(開始.elapsed());
        }
        結果
    }
}
