//! 刻みを回す工程が、遊ばない起動でも固定刻みの番号を刻み数ぶん進めることと、台本の区切りが最初の刻みを0と数えた
//! 番号で効くことと、終了時の報告のゲーム更新の回数が回した刻みの本数になることの検証。実画面もレンダラーも使わず、世界実行と時間進行配線だけで組む。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」。

use blitz_game::ゲームの進行段階;
use blitz_math::{ラジアン, 秒};

use super::game_steps::刻み数ぶんの固定刻みを回す;
use crate::app::time_step::{時間進行方針, 時間進行配線, 進める刻み数};
use crate::app::固定刻みの番号;
use crate::cli::{ゲーム操作の出どころ, 起動モード, 遊ぶゲームの指定};
use crate::input::{カメラ操作の適用方針, 入力状態};
use crate::world_execution::contract::読込済みチャンクの形の出どころ;
use crate::world_execution::世界実行;

fn 検証の時間進行() -> 時間進行配線 {
    時間進行配線::起動モードから作る(起動モード::無期限実行, 時間進行方針::生成する(秒::生成する(1.0 / 60.0), 進める刻み数::生成する(4)))
}

/// 反証: 遊ばない起動で番号を進めないと、布とアニメーション時刻が固定刻みで進むのに番号だけが起動時の最初に留まる。
#[test]
fn 遊ばない起動でも固定刻みの番号は刻み数ぶん進む() {
    let mut 世界実行 = 世界実行::起動設定から作る(遊ぶゲームの指定::ゲームを遊ばない, 起動モード::無期限実行);
    let mut 時間進行 = 検証の時間進行();
    let 結果 = 刻み数ぶんの固定刻みを回す(&mut 世界実行, &mut 時間進行, None, 読込済みチャンクの形の出どころ::ストリーミングを使わない起動, 進める刻み数::生成する(3));
    assert!(結果.is_ok());
    assert_eq!(時間進行.現在の固定刻みの番号(), 固定刻みの番号::起動時の最初().本数だけ後の番号(3));
}

/// 台本の決定は30番目の刻みに当たる。30本回した後はまだタイトル、31本回した後は場所巡り中である。
/// 番号が最初の刻みで0でなければ、この境目が1刻みずれる。
#[test]
fn 台本の決定は最初の刻みを0と数えた30番目の刻みで効く() {
    let モード = 起動モード::スモーク実行 { 描画機会の数: 1 };
    for (本数, 期待) in [(30u16, ゲームの進行段階::タイトル表示中), (31u16, ゲームの進行段階::場所巡り中)] {
        let mut 世界実行 = 世界実行::起動設定から作る(遊ぶゲームの指定::キツネの場所巡り(ゲーム操作の出どころ::決定的な台本), モード);
        let mut 時間進行 = 検証の時間進行();
        let mut 入力状態 = 入力状態::生成する(カメラ操作の適用方針::起動モードから決める(モード));
        let 刻み数 = 進める刻み数::生成する(本数);
        let 器 = 世界実行.この描画で進める刻みへ配る操作入力を確定する(&mut 入力状態, 刻み数, ラジアン::生成する(0.0));
        let 結果 = 刻み数ぶんの固定刻みを回す(&mut 世界実行, &mut 時間進行, 器, 読込済みチャンクの形の出どころ::ストリーミングを使わない起動, 刻み数);
        assert!(結果.is_ok());
        let Some(表示内容) = 世界実行.この描画の描画供給を作る().画面へ重ねる表示内容 else {
            panic!("キツネの場所巡りが画面の表示内容を持たない");
        };
        assert_eq!(表示内容.進行段階, 期待, "{本数}本回した後");
    }
}

/// 反証: 番号が最初の刻みで0でないか、報告が番号を本数へ写すときに1つずらすと、N本回した後の回数がNにならない。
#[test]
fn 終了時の報告のゲーム更新の回数は回した刻みの本数になる() {
    let モード = 起動モード::スモーク実行 { 描画機会の数: 1 };
    let mut 世界実行 = 世界実行::起動設定から作る(遊ぶゲームの指定::キツネの場所巡り(ゲーム操作の出どころ::決定的な台本), モード);
    let mut 時間進行 = 検証の時間進行();
    let mut 入力状態 = 入力状態::生成する(カメラ操作の適用方針::起動モードから決める(モード));
    let 刻み数 = 進める刻み数::生成する(7);
    let 器 = 世界実行.この描画で進める刻みへ配る操作入力を確定する(&mut 入力状態, 刻み数, ラジアン::生成する(0.0));
    let 結果 = 刻み数ぶんの固定刻みを回す(&mut 世界実行, &mut 時間進行, 器, 読込済みチャンクの形の出どころ::ストリーミングを使わない起動, 刻み数);
    assert!(結果.is_ok());
    let Some(要約) = 世界実行.進行の要約を作る(時間進行.現在の固定刻みの番号()) else {
        panic!("キツネの場所巡りが進行の要約を持たない");
    };
    assert_eq!(要約.ゲーム更新の回数, 7);
}
