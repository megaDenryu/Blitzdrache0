//! 描画入力が借用する4つの受け皿をアプリの外へ預け、描画の成否によらず必ず戻す工程。
//! 担当するのは預け・詰め直し・描画・戻しの順序と、途中で失敗しても戻しを飛ばさない規律である。
//!
//! 預けるのは、描画が`&mut アプリ`を要るのに対し、描画入力が同じアプリの中の受け皿を借用で持つためである。
//! 確保した容量を次のフレームへ持ち越すため、戻しは早期returnの外に置く。
//! 動く個体の受け皿が持つのは、この描画の割合で混ぜ終えた位置と向きである(混ぜるのはこの工程より前に済んでいる)。
//! プリミティブ発行を預けた後に詰め直すのは、束の追加と解除がこのフレームまでに済んでおり、台帳の中身が確定しているためである。

use blitz_render::UI描画データ;
use blitz_render::布フレーム入力;

use super::super::draw_dispatch::フレーム材料;
use super::super::アプリ;
use super::draw_input::フレーム視点;
use crate::error::起動エラー;
use crate::smoke::スモークアクション;

pub(super) fn 受け皿を預けて描画する(
    アプリ: &mut アプリ,
    アクション: スモークアクション,
    視点情報: &フレーム視点,
    布入力: Option<布フレーム入力>,
    ui描画: Option<UI描画データ>,
) -> Result<(), 起動エラー> {
    let 段選択受け皿 = アプリ.ストリーミング.as_mut().map_or_else(Vec::new, |配線| 配線.地形詳細段選択を預かる());
    let 可視受け皿 = アプリ.可視判定.受け皿を預ける();
    let mut 発行受け皿 = アプリ.プリミティブ描画項目台帳.発行受け皿を預ける();
    let 動く個体の受け皿 = アプリ.ゲーム配線.動く個体の大域の位置と向きの指定一覧を預ける();
    let 結果 = アプリ.プリミティブ描画項目台帳.発行受け皿へ詰め直す(&mut 発行受け皿).and_then(|()| {
        アプリ.描画まで進める(フレーム材料 {
            アクション,
            視点情報,
            地形詳細段選択一覧: &段選択受け皿,
            可視受け皿: &可視受け皿,
            プリミティブ発行: &発行受け皿,
            動く個体の大域の位置と向きの指定一覧: &動く個体の受け皿,
            布入力,
            ui描画,
        })
    });
    アプリ.ゲーム配線.動く個体の大域の位置と向きの指定一覧を戻す(動く個体の受け皿);
    アプリ.プリミティブ描画項目台帳.発行受け皿を戻す(発行受け皿);
    アプリ.可視判定.受け皿を戻す(可視受け皿);
    if let Some(配線) = &mut アプリ.ストリーミング {
        配線.地形詳細段選択を返す(段選択受け皿);
    }
    結果
}
