//! そのフレームの視点を求める工程。受け取るのはアプリの現在状態、返すのはカメラ相対フレームのビュー射影と
//! カメラの大域位置と透視投影の逆をたどる4つの量である。
//!
//! 描画入力の組み立てと分けるのは、この3つが可視判定と描画入力の両方へ配られる値であり、1フレームに1度だけ
//! 作られるためである。描画入力はこの結果を借用するだけで、どう組み立てられたかを知らない。

use blitz_math::{クリップ, ワールド, 変換};

use crate::app::アプリ;

/// カメラ相対フレームのビュー射影と、その組み立てに使うカメラの大域位置。可視判定と描画入力が同じ値を使うため、
/// 1フレームに1度だけ作って両方へ配る。
pub(crate) struct フレーム視点 {
    pub(crate) ビュー射影: 変換<ワールド, クリップ>,
    pub(crate) カメラ大域位置: blitz_math::大域ワールド位置,
    /// 同じ視点のビュー射影を組み立てた透視投影の4つの量。局所可視性補正が深度から位置を戻すために読む。
    pub(crate) 射影の復元: blitz_render::local_visibility::射影の復元,
}

pub(in crate::app) fn 視点を求める(アプリ: &アプリ) -> フレーム視点 {
    let アスペクト比 = アプリ
        .window
        .as_ref()
        .map(|window| crate::app::aspect::計算する(window.inner_size()))
        .unwrap_or(1.0);
    フレーム視点 {
        射影の復元: 射影の復元を組み立てる(&アプリ.カメラ, アスペクト比),
        ビュー射影: アプリ.カメラ.カメラ相対ビュー射影変換を作る(アスペクト比),
        // カメラ大域原点はカメラ自身の大域位置に置く。相対フレームの原点をカメラへ固定すると、視点近傍の対象の相対座標が最小になる。
        カメラ大域位置: カメラ大域位置を組み立てる(アプリ.カメラ.視点ワールド位置(), アプリ.大域ずらし量),
    }
}

/// カメラが持つ3つの量とその場のアスペクト比から、透視投影の逆をたどる4つの量を作る。
///
/// 失敗をエラーとして運ばないのは、3つの量がカメラの定数であり、アスペクト比が幅と高さを1で下限に取った比だからである。
/// この組み合わせで値域を外れることはプログラムの誤りであり、回復のしようが無い。
fn 射影の復元を組み立てる(
    カメラ: &blitz_engine::カメラ, アスペクト比: f32
) -> blitz_render::local_visibility::射影の復元 {
    blitz_render::local_visibility::射影の復元::生成する(カメラ.近クリップ(), カメラ.遠クリップ(), カメラ.縦視野角(), アスペクト比)
        .unwrap_or_else(|誤り| panic!("カメラの透視投影から射影の復元が作れない(不変条件が破れている): {誤り}"))
}

pub(in crate::app) fn カメラ大域位置を組み立てる(
    局所位置: blitz_math::位置<blitz_math::ワールド>,
    大域ずらし量: blitz_math::大域ワールド位置,
) -> blitz_math::大域ワールド位置 {
    blitz_math::大域ワールド位置::局所ワールド位置から生成する(局所位置).平行移動する(大域ずらし量)
}
