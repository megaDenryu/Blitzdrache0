//! そのフレームの視点を求める工程。受け取るのはアプリの現在状態、返すのは3本のビュー射影と
//! カメラの大域位置と透視投影の逆をたどる4つの量である。
//!
//! 描画入力の組み立てと分けるのは、この3つが可視判定と描画入力の両方へ配られる値であり、1フレームに1度だけ
//! 作られるためである。描画入力はこの結果を借用するだけで、どう組み立てられたかを知らない。
//!
//! 画素内ずらしを注入する地点はここ1箇所である。1つのビュー射影がここから4つの用途へ分岐するため、
//! 注入をこれより下流へ置くと、どの用途がずらしを受けたかを追う手段が無くなる。
//! 参照: `_doc/設計/時間再構成.md`「判断a」

use blitz_engine::temporal_reconstruction::{ずらしの列の添字, 画素を単位とするずらしを求める};
use blitz_math::{クリップ, 変換, 画素内ずらし};
use blitz_render::temporal_reconstruction::時間再構成方式;
use blitz_render::ビュー射影の組;
use winit::dpi::PhysicalSize;

use crate::app::アプリ;

/// カメラ相対フレームの3本のビュー射影と、その組み立てに使うカメラの大域位置。可視判定と描画入力が同じ値を使うため、
/// 1フレームに1度だけ作って両方へ配る。
pub(crate) struct フレーム視点 {
    pub(crate) ビュー射影の組: ビュー射影の組,
    pub(crate) カメラ相対ビュー変換: blitz_math::変換<blitz_math::ワールド, blitz_math::ビュー>, // クラスタの選別が局所光の位置をビュー空間へ写すために読む
    pub(crate) カメラ大域位置: blitz_math::大域ワールド位置,
    pub(crate) 射影の復元: blitz_render::local_visibility::射影の復元, // 同じ視点のビュー射影を組み立てた透視投影の4つの量と画素内ずらし。局所可視性補正が深度から位置を戻すために読む
}

pub(in crate::app) fn 視点を求める(アプリ: &アプリ) -> フレーム視点 {
    let 物理寸法 = アプリ.window.as_ref().map(|window| window.inner_size());
    let アスペクト比 = 物理寸法.map_or(1.0, crate::app::aspect::計算する);
    let ずらし = 画素内ずらしを決める(アプリ, 物理寸法);
    let ずらし無し = アプリ.カメラ.カメラ相対ビュー射影変換を作る(アスペクト比);
    let ずらし付き = ずらし無し.合成する(変換::<クリップ, クリップ>::画素内ずらし(ずらし));
    // カメラ大域原点はカメラ自身の大域位置に置く。相対フレームの原点をカメラへ固定すると、視点近傍の対象の相対座標が最小になる。
    let カメラ大域位置 = カメラ大域位置を組み立てる(アプリ.カメラ.視点ワールド位置(), アプリ.大域ずらし量);
    let 前フレーム = アプリ.視点の履歴.前フレームのビュー射影を今の原点で表す(ずらし無し, カメラ大域位置);
    フレーム視点 {
        射影の復元: 射影の復元を組み立てる(&アプリ.カメラ, アスペクト比, ずらし),
        ビュー射影の組: ビュー射影の組::生成する(ずらし無し, ずらし付き, 前フレーム),
        カメラ相対ビュー変換: アプリ.カメラ.カメラ相対ビュー変換を作る(),
        カメラ大域位置,
    }
}

/// そのフレームの画素内ずらし。方式が使わないの世界と、ウィンドウがまだ無い時点では零である。
///
/// 零を保つことが、時間再構成を使わない全世界の絵が1画素も動かない根拠になる。列から採るのは履歴混合の世界だけであり、
/// フレーム番号を列の長さで折り返した添字が標本の位置を決める(`参照: _doc/設計/時間再構成.md`「判断fの段2での確定」)。
fn 画素内ずらしを決める(アプリ: &アプリ, 物理寸法: Option<PhysicalSize<u32>>) -> 画素内ずらし {
    if アプリ.世界の描画構成.時間再構成の描画設定.方式 != 時間再構成方式::履歴混合 {
        return 画素内ずらし::ずらさない();
    }
    let Some(寸法) = 物理寸法 else {
        return 画素内ずらし::ずらさない();
    };
    let 添字 = ずらしの列の添字::フレーム番号から求める(アプリ.現在フレーム);
    let 画素の量 = 画素を単位とするずらしを求める(添字)
        .unwrap_or_else(|誤り| panic!("ずらしの列が画素を単位とするずらしを作れない(不変条件が破れている): {誤り}"));
    画素の量
        .正規化装置座標へ写す(寸法.width.max(1), 寸法.height.max(1))
        .unwrap_or_else(|誤り| panic!("画素内ずらしを正規化装置座標へ写せない(不変条件が破れている): {誤り}"))
}

/// カメラが持つ3つの量とその場のアスペクト比と画素内ずらしから、透視投影の逆をたどる量を作る。
///
/// 失敗をエラーとして運ばないのは、3つの量がカメラの定数であり、アスペクト比が幅と高さを1で下限に取った比だからである。
/// この組み合わせで値域を外れることはプログラムの誤りであり、回復のしようが無い。
fn 射影の復元を組み立てる(
    カメラ: &blitz_engine::カメラ,
    アスペクト比: f32,
    ずらし: 画素内ずらし,
) -> blitz_render::local_visibility::射影の復元 {
    blitz_render::local_visibility::射影の復元::生成する(カメラ.近クリップ(), カメラ.遠クリップ(), カメラ.縦視野角(), アスペクト比, ずらし)
        .unwrap_or_else(|誤り| panic!("カメラの透視投影から射影の復元が作れない(不変条件が破れている): {誤り}"))
}

pub(in crate::app) fn カメラ大域位置を組み立てる(
    局所位置: blitz_math::位置<blitz_math::ワールド>,
    大域ずらし量: blitz_math::大域ワールド位置,
) -> blitz_math::大域ワールド位置 {
    blitz_math::大域ワールド位置::局所ワールド位置から生成する(局所位置).平行移動する(大域ずらし量)
}
