//! 前フレームの視点の記録。担当するのは、前フレームのずらし無しビュー射影とそのときのカメラ大域原点だけを保ち、
//! 今フレームのカメラ大域原点で表し直した1つの変換を返すことである。
//!
//! 呼ばれるのは1フレームに2度で、視点を求める途中に読み、視点が定まった直後に書く。
//!
//! 表し直しは、今フレームの原点から前フレームの原点を引いた平行移動を前フレームのビュー射影へ右から掛ける形で行う。
//! 右から掛けるのは、今フレームの原点で表された位置を先に前フレームの原点で表し直してから、前フレームの射影を
//! 適用する順だからである。差はf64で取るため、GPUへ渡る値はカメラの1フレームぶんの移動量にとどまる。
//! 参照: `_doc/設計/時間再構成.md`「判断b」

use blitz_math::{クリップ, ワールド, 位置, 変換, 大域ワールド位置};

/// 前フレームが存在しない起動直後は`None`である。
pub(in crate::app) struct 視点の履歴 {
    前フレーム: Option<前フレームの視点>,
}

struct 前フレームの視点 {
    ずらし無しビュー射影: 変換<ワールド, クリップ>,
    カメラ大域原点: 大域ワールド位置,
}

impl 視点の履歴 {
    pub(in crate::app) fn 記録なしで生成する() -> Self {
        Self { 前フレーム: None }
    }

    /// 今フレームのカメラ大域原点で表し直した前フレームのビュー射影。
    ///
    /// 起動直後の最初のフレームは前フレームが無いため、今フレームのずらし無しビュー射影をそのまま返す。
    /// 動きが零であることの表明であり、この規約は`_doc/設計/時間再構成.md`「判断b」が正本である。
    pub(in crate::app) fn 前フレームのビュー射影を今の原点で表す(
        &self,
        今のずらし無しビュー射影: 変換<ワールド, クリップ>,
        今のカメラ大域原点: 大域ワールド位置,
    ) -> 変換<ワールド, クリップ> {
        let Some(前) = &self.前フレーム else {
            return 今のずらし無しビュー射影;
        };
        let ずれ = 原点の差を求める(今のカメラ大域原点, 前.カメラ大域原点);
        変換::平行移動(ずれ).合成する(前.ずらし無しビュー射影)
    }

    pub(in crate::app) fn 記録する(
        &mut self, ずらし無しビュー射影: 変換<ワールド, クリップ>, カメラ大域原点: 大域ワールド位置
    ) {
        self.前フレーム = Some(前フレームの視点 {
            ずらし無しビュー射影,
            カメラ大域原点,
        });
    }
}

/// 今フレームの原点から前フレームの原点を引いた量。1フレームぶんのカメラの移動量であり、単精度で表せる桁に収まる。
///
/// 収まらないのはカメラが1フレームで単精度の表現範囲を超えて跳んだときだけであり、これは回復のしようがない
/// 不変条件の破れである。同じファイル群の`射影の復元`の組み立てと同じ扱いにする。
fn 原点の差を求める(
    今のカメラ大域原点: 大域ワールド位置, 前のカメラ大域原点: 大域ワールド位置
) -> 位置<ワールド> {
    let 差 = 今のカメラ大域原点
        .カメラ相対へ変換する(前のカメラ大域原点)
        .unwrap_or_else(|誤り| panic!("1フレームのカメラ大域原点の差が単精度に収まらない(不変条件が破れている): {誤り}"));
    位置::生成する(差.x(), 差.y(), 差.z())
}
