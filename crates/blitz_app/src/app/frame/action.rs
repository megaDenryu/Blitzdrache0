//! 起動モードと検証対象から現在フレームのスモークアクションを選ぶ。

use super::super::アプリ;
use crate::cli::起動モード;
use crate::smoke::{self, スモークアクション};

pub(super) fn 選ぶ(アプリ: &アプリ) -> スモークアクション {
    match アプリ.起動モード {
        // ウィンドウ再構築検証はピクセル判定を持たないため、シーン・粒子等による計画選択より先に決める。
        起動モード::スモーク実行 { フレーム数 } if アプリ.ウィンドウ再構築検証有効 => {
            smoke::ウィンドウ再構築計画(アプリ.現在フレーム, フレーム数)
        }
        // ストリーミングを有効にした実行は、起動時シーンの絵へチャンクが重なるため既存のピクセル判定が絵を言い当てない。
        // 合否はvalidation件数と読み戻し画像で決める。
        起動モード::スモーク実行 { .. } if アプリ.ストリーミング.is_some() => スモークアクション::通常描画,
        起動モード::スモーク実行 { フレーム数 } => smoke::判定する(
            アプリ.現在フレーム,
            フレーム数,
            &アプリ.シーン名,
            アプリ.粒子表示,
            アプリ.開発ui初期有効,
            アプリ.布モード != crate::cli::布モード::なし,
            アプリ.描画対象の並べ方.件数,
        ),
        起動モード::ベンチ実行 { .. } | 起動モード::無期限実行 => スモークアクション::通常描画,
    }
}
