//! そのフレームの自己操作をスモーク実行へ問い合わせる。`--frames`以外の起動はスモーク実行を持たないため、
//! 自己操作を1つも踏まない通常描画になる。計画の選び方はスモーク実行が持つ。

use super::super::time_step::フレーム番号;
use super::super::アプリ;
use crate::smoke::スモークアクション;

pub(super) fn 選ぶ(アプリ: &アプリ, フレーム番号: フレーム番号) -> スモークアクション {
    let Some(スモーク実行) = &アプリ.スモーク実行 else {
        return スモークアクション::通常描画;
    };
    スモーク実行.このフレームの動作を決める(フレーム番号.境界用の生値())
}
