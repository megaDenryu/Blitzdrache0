//! 起動モードと検証対象から現在フレームのスモークアクションを選ぶ。

use super::super::アプリ;
use crate::cli::起動モード;
use crate::smoke::{self, スモークアクション};

pub(super) fn 選ぶ(アプリ: &アプリ) -> スモークアクション {
    match アプリ.起動モード {
        起動モード::スモーク実行 { フレーム数 } => smoke::判定する(
            アプリ.現在フレーム,
            フレーム数,
            &アプリ.シーン名,
            アプリ.粒子表示,
            アプリ.開発ui初期有効,
            アプリ.布モード != crate::cli::布モード::なし,
            アプリ.描画対象数,
        ),
        起動モード::ベンチ実行 { .. } | 起動モード::無期限実行 => スモークアクション::通常描画,
    }
}
