//! 起動モードと検証対象から現在フレームのスモークアクションを選ぶ。

use super::super::アプリ;
use crate::cli::{検証計画指定, 起動モード};
use crate::smoke::{self, スモークアクション};

pub(super) fn 選ぶ(アプリ: &アプリ) -> スモークアクション {
    let 起動モード::スモーク実行 { フレーム数 } = アプリ.起動モード else {
        return スモークアクション::通常描画;
    };
    // 起動指定が直に選ぶ計画はどちらもピクセル判定を持たないため、シーン・粒子等による計画選択より先に決める。
    match アプリ.検証計画 {
        検証計画指定::ウィンドウ再構築 => {
            return smoke::現在フレームからウィンドウ再構築の動作を導出する(アプリ.現在フレーム, フレーム数);
        }
        検証計画指定::シェーダー差し替え => {
            return smoke::現在フレームからシェーダー差し替えの動作を導出する(アプリ.現在フレーム, フレーム数);
        }
        検証計画指定::指定なし => {}
    }
    // ストリーミングを有効にした実行は、起動時シーンの絵へチャンクが重なるため既存のピクセル判定が絵を言い当てない。
    // 合否はvalidation件数と読み戻し画像で決める。
    if アプリ.ストリーミング.is_some() {
        return スモークアクション::通常描画;
    }
    smoke::判定する(
        アプリ.現在フレーム,
        フレーム数,
        &アプリ.シーン名,
        アプリ.粒子表示,
        アプリ.開発ui初期有効,
        アプリ.布モード != crate::cli::布モード::なし,
        アプリ.描画対象の並べ方.件数,
    )
}
