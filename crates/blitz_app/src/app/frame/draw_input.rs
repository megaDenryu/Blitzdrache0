//! そのフレームの描画入力を組み立てる工程。受け取るのはアプリの現在状態と、借用で渡す地形の詳細段選択・可視個体選択、
//! 返すのはレンダラーへ渡す1フレーム分の入力である。
//! 視点・ライティング・スキン行列という出どころの違う値を1つの入力へ集める場所であり、呼び出し元は中身の集め方を知らない。
//! 3つの借用だけを引数で受けるのは、返す入力がこれらを借用し、借用元をアプリの外へ出しておく必要があるためである。

use blitz_math::{クリップ, ワールド, 変換};

use super::super::アプリ;
use blitz_render::frame_input::影のキャスター指定;

/// 起動指定から来る、描画入力の絵と費用を計測のために変える2つのつまみ。実行中は変わらない。
/// 1つの型へまとめるのは、どちらも本番の既定から外れた対照を作るためだけの指定であり、
/// アプリのフィールドとして別々に並べる理由が無いためである。
#[derive(Clone, Copy)]
pub(in crate::app) struct 描画の計測つまみ {
    /// `--debug-cascade-bands`と`--debug-shadow-loss`が選ぶ、シーンの色に代えて出す診断。
    pub(in crate::app) 画素診断: blitz_render::cascade::画素診断,
    /// `--no-shadow-casters`で`全て外す`。距離区分のパスへ描画入力を1件も積まない対照になる。
    pub(in crate::app) 影のキャスター: 影のキャスター指定,
}

impl 描画の計測つまみ {
    pub(in crate::app) fn 起動設定から作る(画素診断: blitz_render::cascade::画素診断, 影キャスター全体有効: bool) -> Self {
        Self {
            画素診断,
            影のキャスター: if 影キャスター全体有効 {
                影のキャスター指定::通常に描く
            } else {
                影のキャスター指定::全て外す
            },
        }
    }
}

/// カメラ相対フレームのビュー射影と、その組み立てに使うカメラの大域位置。可視判定と描画入力が同じ値を使うため、
/// 1フレームに1度だけ作って両方へ配る。
pub(in crate::app) struct フレーム視点 {
    pub(in crate::app) ビュー射影: 変換<ワールド, クリップ>,
    pub(in crate::app) カメラ大域位置: blitz_math::大域ワールド位置,
}

pub(in crate::app) fn 視点を求める(アプリ: &アプリ) -> フレーム視点 {
    let アスペクト比 = アプリ
        .window
        .as_ref()
        .map(|window| crate::app::aspect::計算する(window.inner_size()))
        .unwrap_or(1.0);
    フレーム視点 {
        ビュー射影: アプリ.カメラ.カメラ相対ビュー射影変換を作る(アスペクト比),
        // カメラ大域原点はカメラ自身の大域位置に置く。相対フレームの原点をカメラへ固定すると、視点近傍の対象の相対座標が最小になる。
        カメラ大域位置: カメラ大域位置を組み立てる(アプリ.カメラ.視点ワールド位置(), アプリ.大域ずらし量),
    }
}

pub(in crate::app) fn 組み立てる<'a>(
    アプリ: &アプリ,
    焼き上げ入力: crate::app::time_of_day::焼き上げ入力の組,
    視点情報: &フレーム視点,
    地形詳細段選択一覧: &'a [blitz_render::地形詳細段選択],
    可視個体選択一覧: blitz_render::可視個体選択一覧<'a>,
    プリミティブ発行: &'a blitz_render::frame_input::プリミティブ発行受け皿,
) -> blitz_render::フレーム描画入力<'a> {
    let カメラ大域原点 = 視点情報.カメラ大域位置;
    let 視点 = blitz_render::描画視点::生成する(視点情報.ビュー射影, 視点情報.カメラ大域位置, カメラ大域原点);
    let 視点一覧 = blitz_render::描画視点一覧::生成する(視点, Vec::new());
    if アプリ.現在フレーム == 0 && アプリ.描画対象の並べ方.件数.is_some() {
        crate::reports::composition::描画視点構成を表示する(視点一覧.視点数());
        let 原点 = blitz_math::大域ワールド位置::原点();
        crate::reports::composition::座標変換を表示する(原点, 原点.カメラ相対へ変換する(カメラ大域原点));
    }
    blitz_render::フレーム描画入力 {
        クリア色: アプリ.クリア色,
        視点一覧,
        ライティング: アプリ.天空.ライティング(),
        空: アプリ.天空.空入力(),
        大気: 焼き上げ入力.大気,
        遠方環境: 焼き上げ入力.遠方環境,
        露出: アプリ.天空.露出倍率(アプリ.露出),
        スキン行列一覧: アプリ
            .アニメーション
            .as_ref()
            .map(|再生| 再生.スキン行列を計算する(アプリ.アニメ時刻秒, アプリ.ブレンド)),
        布: None,
        ui描画: None,
        影のキャスター: アプリ.計測つまみ.影のキャスター,
        画素診断: アプリ.計測つまみ.画素診断,
        地形詳細段選択一覧,
        可視個体選択一覧,
        プリミティブ発行,
    }
}

pub(super) fn カメラ大域位置を組み立てる(
    局所位置: blitz_math::位置<blitz_math::ワールド>,
    大域ずらし量: blitz_math::大域ワールド位置,
) -> blitz_math::大域ワールド位置 {
    blitz_math::大域ワールド位置::局所ワールド位置から生成する(局所位置).平行移動する(大域ずらし量)
}
