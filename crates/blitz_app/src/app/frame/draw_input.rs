//! そのフレームの描画入力を組み立てる工程。受け取るのは焼き上げ入力と視点と、借用で渡す地形の詳細段選択・可視個体選択、
//! 返すのはレンダラーへ渡す1フレーム分の入力である。`アプリ`のメソッドなのは、クリア色・天空・露出・アニメーション・計測つまみという
//! 出どころの違う自分のフィールドを1つの入力へ集めるコンポジションルートの工程だからである。
//! 視点・ライティング・スキン行列という出どころの違う値を1つの入力へ集める場所であり、呼び出し元は中身の集め方を知らない。
//! 4つの借用だけを引数で受けるのは、返す入力がこれらを借用し、借用元をアプリの外へ出しておく必要があるためである。
//! そのフレームの視点そのものを求める工程は視点の配線が持つ。

use super::super::view_wiring::フレーム視点;
use super::super::アプリ;
use blitz_render::frame_input::影のキャスター指定;

/// 起動指定から来る、描画入力の絵と費用を計測のために変える2つのつまみ。実行中は変わらない。
/// 1つの型へまとめるのは、どちらも本番の既定から外れた対照を作るためだけの指定であり、
/// アプリのフィールドとして別々に並べる理由が無いためである。
#[derive(Clone, Copy)]
pub(in crate::app) struct 描画の計測つまみ {
    pub(in crate::app) 画素診断: blitz_render::cascade::画素診断, // --debug-cascade-bandsと--debug-shadow-lossが選ぶ、シーンの色に代えて出す診断
    pub(in crate::app) 影のキャスター: 影のキャスター指定,        // --no-shadow-castersで全て外す。距離区分のパスへ描画入力を1件も積まない対照になる
}

impl 描画の計測つまみ {
    pub(in crate::app) fn 起動設定から作る(画素診断: blitz_render::cascade::画素診断, 影キャスター全体有効: bool) -> Self {
        Self {
            画素診断,
            影のキャスター: if 影キャスター全体有効 {
                影のキャスター指定::通常に描く
            } else {
                影のキャスター指定::全て外す
            },
        }
    }
}

impl アプリ {
    pub(in crate::app) fn 描画入力を組み立てる<'a>(
        &self,
        焼き上げ入力: crate::app::time_of_day::焼き上げ入力の組,
        視点情報: &フレーム視点,
        地形詳細段選択一覧: &'a [blitz_render::地形詳細段選択],
        可視個体選択一覧: blitz_render::可視個体選択一覧<'a>,
        プリミティブ発行: &'a blitz_render::frame_input::プリミティブ発行受け皿,
        動く個体の大域の位置と向きの指定一覧: &'a [blitz_render::frame_input::動く個体の大域の位置と向きの指定],
    ) -> Result<blitz_render::フレーム描画入力<'a>, crate::error::起動エラー> {
        let カメラ大域原点 = 視点情報.カメラ大域位置;
        let 視点 = blitz_render::描画視点::生成する(視点情報.ビュー射影の組, 視点情報.カメラ相対ビュー変換, 視点情報.カメラ大域位置, カメラ大域原点, 視点情報.射影の復元);
        let 視点一覧 = blitz_render::描画視点一覧::生成する(視点, Vec::new());
        if 視点情報.描画機会の番号.最初の描画機会か() && self.描画対象の並べ方.件数.is_some() {
            crate::reports::composition::描画視点構成を表示する(視点一覧.視点数());
            let 原点 = blitz_math::大域ワールド位置::原点();
            crate::reports::composition::座標変換を表示する(原点, 原点.カメラ相対へ変換する(カメラ大域原点));
        }
        Ok(blitz_render::フレーム描画入力 {
            クリア色: self.クリア色,
            視点一覧,
            ライティング: self.天空.ライティング(),
            空: self.天空.空入力(),
            大気: 焼き上げ入力.大気,
            遠方環境: 焼き上げ入力.遠方環境,
            露出: self.天空.露出倍率(self.露出)?.値(),
            自動露出の経過秒: self.天空.自動露出の経過秒(),
            スキン行列一覧: self.アニメーション.as_ref().map(|再生| 再生.スキン行列を計算する(self.アニメ時刻, self.ブレンド)),
            布: None,
            ui描画: None,
            影のキャスター: self.計測つまみ.影のキャスター,
            画素診断: self.計測つまみ.画素診断,
            地形詳細段選択一覧,
            可視個体選択一覧,
            動く個体の大域の位置と向きの指定一覧,
            プリミティブ発行,
        })
    }
}
