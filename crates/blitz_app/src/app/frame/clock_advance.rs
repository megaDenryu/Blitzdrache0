//! アニメーション時刻と天空の時計を、その描画で進めた刻み数へ追随させる工程。受け取るのはその描画で進める刻み数、
//! 返すのは無しである。触れるのは`アニメ時刻`と`天空`だけであり、ゲームの確定状態には指を触れない。
//!
//! いつ呼ばれるか: 1描画に1度、固定刻みを進めた後・可視判定より前である。可視判定より前に置くのは、
//! ライト視錐台の導出が方向光の向きを読むためである。
//! 実時間を直に読まないため、同じ本数を進めた実行は必ず同じ時刻で終わり、フレーム数の決まった実行は
//! 毎描画1本で従来と同じ歩進になる。
//! 参照: `_doc/設計/時間の規律.md`「入力の規律」。

use super::super::time_step::進める刻み数;
use super::super::アプリ;

impl アプリ {
    pub(super) fn 時刻と天空をこの描画の刻み数へ追随させる(&mut self, 刻み数: 進める刻み数) {
        let この描画で進んだゲームの時間 = self.時間進行.刻み数ぶんの秒を求める(刻み数);
        self.アニメ時刻 = self.アニメ時刻 + この描画で進んだゲームの時間;
        self.天空.進める(この描画で進んだゲームの時間);
        // 段差の走査は時計を進めた後に条件を据える。据えた時刻を同じフレームの進行が上書きしないためである。
        self.天空.撮影の条件を据える(self.現在フレーム);
        // 自動露出の経過秒は時計の進行と別に確定させる。時計を止めた実行でも露出の追従は進むためである。
        self.天空.自動露出の経過秒を進める();
    }
}
