//! 描画入力のうち、ウィンドウやGPUを要しない大域カメラ位置の組み立てを検査する。

use blitz_math::{メートル, ワールド, 位置, 大域メートル, 大域ワールド位置};

use super::draw_input;

#[test]
fn カメラ大域位置へ三軸の同じずらし量を足す() {
    let 局所位置 = 位置::<ワールド>::生成する(メートル::生成する(10.0), メートル::生成する(20.0), メートル::生成する(30.0));
    let ずらし量 = 大域ワールド位置::生成する(大域メートル::生成する(1.0), 大域メートル::生成する(2.0), 大域メートル::生成する(3.0));
    let 大域位置 = draw_input::frame_view::カメラ大域位置を組み立てる(局所位置, ずらし量);
    assert_eq!([大域位置.x().値(), 大域位置.y().値(), 大域位置.z().値()], [11.0, 22.0, 33.0]);
}
