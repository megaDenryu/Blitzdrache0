//! 一描画の中で必要な本数だけ固定刻みを進める工程。受け取るのはその描画で進める刻み数、返すのは
//! イベントループを閉じるべきかどうかである。刻み数を決めるのは時間進行の配線であり、この工程は決め方を知らない。
//!
//! いつ呼ばれるか: 1描画に1度、入力を確定した直後・カメラの更新より前である。カメラのヨーをここで読むのは、
//! この描画のカメラ操作を反映する前のヨーを全ての刻みへ配るためである。
//!
//! 操作入力の確定を繰り返しの外で1度だけ行うのは、入力の確定が描画の頻度で起きるためである。刻みごとに取り直す形にはできない。
//! 刻み数を確定へ渡すのは、刻みを1本も進めない描画で押し下げの旗を消費させないためである。
//! 刻みの中でゲームの終了が決まったら残りの刻みを回さないのは、終了を決めた後の世界を進めないためである。
//! 読込済みチャンクの形の出どころを刻みへ渡すのは、胴体の移動が世界の形を尋ねるためである。
//! 1刻みの所要時間を測るのは、性能予算の枠(世界の形への問い合わせ0.1ミリ秒)と突き合わせる材料を終了時の報告へ出すためであり、
//! 測った時間はゲームの状態へ1つも影響しない。
//! 参照: `_doc/設計/時間の規律.md`「判断9」「入力の規律」。

use std::time::Instant;

use super::super::time_step::進める刻み数;
use super::super::アプリ;
use crate::error::起動エラー;
use crate::world_execution::contract::{刻み入力, 刻み結果};

impl アプリ {
    pub(in crate::app) fn この描画の刻み数だけゲームを進める(&mut self, 刻み数: 進める刻み数) -> Result<刻み結果, 起動エラー> {
        let Some(mut 刻みごとの操作入力) = self.世界実行.この描画で進める刻みへ配る操作入力を確定する(&mut self.入力状態, 刻み数) else {
            return Ok(刻み結果::続ける);
        };
        let カメラのヨー = self.視点.ヨー();
        let 一刻みの秒 = self.時間進行.基本刻み();
        let 出どころ = self.資源の配線.読込済みチャンクの形の出どころを組む();
        for _ in 0..刻み数.本数() {
            let この刻みの操作入力 = 刻みごとの操作入力.次の刻みぶんを取り出す();
            let 始まり = Instant::now();
            let 結果 = self.世界実行.一刻み進める(刻み入力::カメラのヨーから生成する(この刻みの操作入力, カメラのヨー, 出どころ), 一刻みの秒)?;
            self.世界実行.刻みの所要時間を記録する(始まり.elapsed());
            if 結果 == 刻み結果::終了する {
                return Ok(刻み結果::終了する);
            }
        }
        Ok(刻み結果::続ける)
    }
}
