//! 一描画の中で必要な本数だけ固定刻みを進める工程。受け取るのはその描画で進める刻み数、返すのは
//! イベントループを閉じるべきかどうかである。刻み数を決めるのは時間進行の配線であり、この工程は決め方を知らない。
//!
//! いつ呼ばれるか: 1描画に1度、入力を確定した直後・カメラの更新より前である。カメラのヨーを入力の確定と同じ地点で1度読んで
//! 配る器に載せるのは、この描画のカメラ操作を反映する前のヨーを全ての刻みへ配るためであり、刻みごとにヨーを渡す口は無い。
//!
//! 操作入力の確定を繰り返しの外で1度だけ行うのは、入力の確定が描画の頻度で起きるためである。刻みごとに取り直す形にはできない。
//! 刻み数を確定へ渡すのは、刻みを1本も進めない描画で押し下げの旗を消費させないためである。
//! 刻みの中でゲームの終了が決まったら残りの刻みを回さないのは、終了を決めた後の世界を進めないためである。
//! 読込済みチャンクの形の出どころを刻みへ渡すのは、胴体の移動が世界の形を尋ねるためである。
//! 1刻みの所要時間を測るのは、性能予算の枠(世界の形への問い合わせ0.1ミリ秒)と突き合わせる材料を終了時の報告へ出すためであり、
//! 測った時間はゲームの状態へ1つも影響しない。
//! 固定刻みの番号は刻みを1本進めるごとに進め、ゲームを遊ばない起動でも同じだけ進める。布とアニメーション時刻が
//! 固定刻みで進むためであり、番号は刻みの前に読んで刻み入力へ載せ、刻みの後に進める(最初の刻みが0である)。
//! 繰り返しを`アプリ`から切り出しているのは、遊ばない起動でも番号が進むことを、アプリを組まずに試験で固定するためである。
//! 参照: `_doc/設計/時間の規律.md`「判断9」「入力の規律」、`_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」。

use std::time::Instant;

use super::super::time_step::{時間進行配線, 進める刻み数};
use super::super::アプリ;
use crate::error::起動エラー;
use crate::input::刻みごとの操作入力;
use crate::world_execution::contract::{刻み入力, 刻み結果, 読込済みチャンクの形の出どころ};
use crate::world_execution::世界実行;

impl アプリ {
    pub(in crate::app) fn この描画の刻み数だけゲームを進める(&mut self, 刻み数: 進める刻み数) -> Result<刻み結果, 起動エラー> {
        let 刻みごとの操作入力 = self.世界実行.この描画で進める刻みへ配る操作入力を確定する(&mut self.入力状態, 刻み数, self.視点.ヨー());
        let 出どころ = self.資源の配線.読込済みチャンクの形の出どころを組む();
        刻み数ぶんの固定刻みを回す(&mut self.世界実行, &mut self.時間進行, 刻みごとの操作入力, 出どころ, 刻み数)
    }
}

// 世界実行と時間進行配線の両方を対等に進める工程であり、主語が一意に決まらないため自由関数にする。
// 器が`None`(遊ばない起動)でも番号だけは刻み数ぶん進める。
pub(super) fn 刻み数ぶんの固定刻みを回す(
    世界実行: &mut 世界実行,
    時間進行: &mut 時間進行配線,
    刻みごとの操作入力: Option<刻みごとの操作入力>,
    出どころ: 読込済みチャンクの形の出どころ<'_>,
    刻み数: 進める刻み数,
) -> Result<刻み結果, 起動エラー> {
    let 一刻みの秒 = 時間進行.基本刻み();
    let mut 刻みごとの操作入力 = 刻みごとの操作入力;
    for _ in 0..刻み数.本数() {
        let mut 結果 = 刻み結果::続ける;
        if let Some(器) = 刻みごとの操作入力.as_mut() {
            let 始まり = Instant::now();
            結果 = 世界実行.一刻み進める(刻み入力::配る器から次の刻みぶんを生成する(器, 出どころ, 時間進行.現在の固定刻みの番号()), 一刻みの秒)?;
            世界実行.刻みの所要時間を記録する(始まり.elapsed());
        }
        時間進行.次の固定刻みへ進める();
        if 結果 == 刻み結果::終了する {
            return Ok(刻み結果::終了する);
        }
    }
    Ok(刻み結果::続ける)
}
