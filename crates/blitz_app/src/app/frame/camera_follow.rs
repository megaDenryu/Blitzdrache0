//! ゲームが供給する位置へカメラの注視点を移す工程。受け取るのはこの描画の補間の割合、返すのは無しである。
//! 触れるのは`カメラ`だけであり、ヨー・ピッチ・距離には指を触れない
//! (それらは従来どおりカメラ操作の入力が決める)。
//!
//! いつ呼ばれるか: 1描画に1度、供給値を混ぜた直後・カメラの更新より前である。更新より前に据えるのは、そのフレームの
//! マウス操作を追従後の注視点に対して効かせるためである。
//! `--game`の指定が無い起動ではゲーム配線が位置を1つも返さないため、カメラは1度も触られない。
//!
//! 据える位置が刻み境界の確定値でなく混ぜた値なのは、注視点が描画機会ごとの時間意味に属するためである
//! (参照: `_doc/設計/時間の規律.md`「判断5」「判断6」)。混ぜた注視点はヨーへ回り込まないため、次のゲーム更新が
//! 前へ進む向きとして読む値は補間の影響を1つも受けない(`カメラ::更新する`がヨーを決めるのはカメラ操作の入力だけである)。

use super::super::time_step::描画補間の割合;
use super::super::アプリ;

impl アプリ {
    pub(super) fn ゲームが供給する位置へ注視点を移す(&mut self, 補間の割合: 描画補間の割合) {
        let Some(大域位置) = self.ゲーム配線.カメラが追従する混ぜた大域位置(補間の割合) else {
            return;
        };
        // 注視点は局所ワールド位置で持つ。大域ずらし量は局所位置へ後から足される量であるため、ここでは引いて渡す
        // (`app/frame/draw_input/frame_view.rs`の`カメラ大域位置を組み立てる`がその足し算を行う)。
        match 大域位置.局所ワールド位置へ狭める(self.大域ずらし量) {
            Ok(注視点) => self.カメラ.注視点を据える(注視点),
            // 追従の対象がf32で表せない距離まで離れたら、カメラを黙って据え置かず破られた不変条件として止める。
            // 1本目の世界の広さでは到達しない(参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「第1段階の定義」)。
            Err(誤り) => panic!("カメラが追従する大域位置を局所ワールド位置へ狭められない: {誤り}"),
        }
    }
}
