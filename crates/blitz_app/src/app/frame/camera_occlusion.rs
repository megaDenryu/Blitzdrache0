//! この描画の世界を描画機会の時間意味で更新し(描画へ渡す供給値の混ぜ直し)、この描画の表示距離を注視点から理想視点への
//! 遮蔽で決めてエンジンのカメラへ据える工程。受け取るのはこの描画の時間の進み、返すのは無しである。
//! 触れるのは`視点`と`世界実行`と、借りるだけの`資源の配線`と`時間進行`と`大域ずらし量`である。
//!
//! いつ呼ばれるか: 1描画に1度、注視点を据えてカメラ操作で理想距離を更新した直後である。更新より後に置くのは、
//! 更新が表示距離を理想距離へ合わせるため、その前に据えた値が消えるからである。
//! 判定の入力の組み立てと指示の適用は視点の配線が持ち、この工程は世界の形の出どころと世界実行を借りて判定を頼むだけである。
//! 進めた時間は実時間でなく刻み数×基本刻みである(`_doc/設計/キャラクターの移動とカメラ.md`「判断12」)。

use super::super::time_step::この描画の時間の進み;
use super::super::アプリ;
use crate::error::起動エラー;

impl アプリ {
    pub(super) fn 世界を描画機会の時間意味で更新して表示距離を決める(&mut self, 時間の進み: &この描画の時間の進み) -> Result<(), 起動エラー> {
        let 入力 = self.視点.この描画のカメラの入力を組む(self.大域ずらし量, self.時間進行.刻み数ぶんの秒を求める(時間の進み.刻み数()));
        let 出どころ = self.資源の配線.読込済みチャンクの形の出どころを組む();
        let 指示 = self.世界実行.この描画の世界を描画機会の時間意味で更新する(時間の進み.補間の割合(), 出どころ, 入力)?;
        self.視点.表示距離の指示を適用する(指示)
    }
}
