//! この描画の表示距離を、注視点から理想視点への遮蔽で決めてエンジンのカメラへ据える工程。受け取るのはその描画で進めた刻み数、
//! 返すのは無しである。触れるのは`カメラ`と`ゲーム配線`と、借りるだけの`ストリーミング`と`時間進行`と`大域ずらし量`である。
//!
//! いつ呼ばれるか: 1描画に1度、注視点を据えてカメラ操作で理想距離を更新した直後である。更新より後に置くのは、
//! 更新が表示距離を理想距離へ合わせるため、その前に据えた値が消えるからである。
//! 注視点と理想視点は局所ワールド位置で持たれているため、問い合わせへ渡す大域位置は大域ずらし量を足して作る
//! (`draw_input/frame_view.rs`のカメラ大域位置と同じ変換)。進めた時間は実時間でなく刻み数×基本刻みである(判断12)。

use blitz_engine::カメラ;

use super::super::time_step::進める刻み数;
use super::super::アプリ;
use super::カメラ大域位置を組み立てる;
use crate::error::起動エラー;
use crate::game::{この描画のカメラの入力, 表示距離の指示, 読込済みチャンクの形の出どころ};

impl アプリ {
    pub(super) fn カメラの表示距離をこの描画の遮蔽で決める(
        &mut self, 刻み数: 進める刻み数
    ) -> Result<(), 起動エラー> {
        let 入力 = この描画のカメラの入力 {
            注視点: カメラ大域位置を組み立てる(self.カメラ.注視点(), self.大域ずらし量),
            理想視点: カメラ大域位置を組み立てる(self.カメラ.理想の視点ワールド位置(), self.大域ずらし量),
            理想距離: self.カメラ.理想距離(),
            表示距離の下限: カメラ::最小距離(),
            進めた時間: self.時間進行.刻み数ぶんの秒を求める(刻み数),
        };
        let 出どころ = match &self.ストリーミング {
            None => 読込済みチャンクの形の出どころ::ストリーミングを使わない起動,
            Some(配線) => 読込済みチャンクの形の出どころ::ストリーミング調停(配線.調停()),
        };
        match self.ゲーム配線.この描画の表示距離を決める(出どころ, 入力)? {
            表示距離の指示::カメラを触らない => Ok(()),
            表示距離の指示::据える(表示距離) => Ok(self.カメラ.表示距離を据える(表示距離)?),
        }
    }
}
