//! この描画の表示距離を、注視点から理想視点への遮蔽で決めてエンジンのカメラへ据える工程。受け取るのはその描画で進めた刻み数、
//! 返すのは無しである。触れるのは`視点`と`ゲーム配線`と、借りるだけの`資源の配線`と`時間進行`と`大域ずらし量`である。
//!
//! いつ呼ばれるか: 1描画に1度、注視点を据えてカメラ操作で理想距離を更新した直後である。更新より後に置くのは、
//! 更新が表示距離を理想距離へ合わせるため、その前に据えた値が消えるからである。
//! 判定の入力の組み立てと指示の適用は視点の配線が持ち、この工程は世界の形の出どころとゲーム配線を借りて判定を頼むだけである。
//! 進めた時間は実時間でなく刻み数×基本刻みである(`_doc/設計/キャラクターの移動とカメラ.md`「判断12」)。

use super::super::time_step::進める刻み数;
use super::super::アプリ;
use crate::error::起動エラー;

impl アプリ {
    pub(super) fn カメラの表示距離をこの描画の遮蔽で決める(&mut self, 刻み数: 進める刻み数) -> Result<(), 起動エラー> {
        let 入力 = self.視点.この描画のカメラの入力を組む(self.大域ずらし量, self.時間進行.刻み数ぶんの秒を求める(刻み数));
        let 出どころ = self.資源の配線.読込済みチャンクの形の出どころを組む();
        let 指示 = self.ゲーム配線.この描画の表示距離を決める(出どころ, 入力)?;
        self.視点.表示距離の指示を適用する(指示)
    }
}
