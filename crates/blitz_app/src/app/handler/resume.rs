//! `resumed`が呼ばれたときの生成と格納の局面。呼ばれるのは起動時の1回だけであり、イベントごとに呼ばれる`window_event`とは
//! 呼び出し頻度も触れるフィールドも違う。担当するのは、ウィンドウとレンダラーの生成を頼み、返ってきた一式をアプリのフィールドへ
//! 収め、束ごとの台帳へ起動時シーンを登録することである。生成そのものの手順は`window_setup`が持つ。

use winit::event_loop::ActiveEventLoop;

use crate::app::アプリ;

pub(super) fn 生成してアプリへ格納する(アプリ: &mut アプリ, event_loop: &ActiveEventLoop) {
    let 実表示計測要求 = crate::app::measurement_setup::実表示計測要求を決める(アプリ);
    match crate::app::window_setup::ウィンドウとレンダラーを作る(
        event_loop,
        &アプリ.シーン名,
        &アプリ.アセットルート,
        アプリ.描画対象の並べ方,
        &mut アプリ.ホットリローダー,
        アプリ.粒子表示,
        アプリ.空中遠近合成,
        アプリ.開発ui初期有効,
        アプリ.世界の描画構成.フレーム構成,
        アプリ.布モード,
        実表示計測要求,
        アプリ.大域ずらし量,
        アプリ.天空.影の一辺解像度(),
        アプリ.天空.照明問い合わせ契約(),
        アプリ.天空.自動露出の設定(),
        アプリ.世界の描画構成.局所可視性の描画設定,
        アプリ.世界の描画構成.時間再構成の描画設定,
        &mut アプリ.ゲーム配線,
    ) {
        Ok((window, mut レンダラー, 開発ui, アニメーション, 布プリセット, 登録一式)) => {
            // 起動時シーンをディスクから読んだのはこの1回である。
            アプリ.シーン読込計数.読み込んだ(アプリ.現在フレーム);
            crate::reports::composition::ディスクリプタ索引上限を表示する(レンダラー.ディスクリプタ索引上限を取得する());
            if let Some(状況) = crate::app::measurement_setup::レンダラーの計測を有効にする(&mut レンダラー, アプリ) {
                println!("実表示時刻計測: {}", 状況.名称());
            }
            let 注入 = アプリ
                .読み戻し検収
                .遠方環境の検収条件
                .map(|条件| crate::reports::indirect_probe::レンダラーへ注入する(条件, &mut レンダラー));
            if let Some(Err(誤り)) = 注入 {
                アプリ.起動時エラー = Some(crate::error::起動エラー::from(誤り));
                event_loop.exit();
                return;
            }
            let 束id = crate::app::scene_load::起動時シーンの束ID;
            アプリ.可視判定.束を登録する(束id, 登録一式.可視材料一覧);
            アプリ.プリミティブ描画項目台帳.束を登録する(束id, 登録一式.プリミティブ描画項目一覧);
            アプリ.window = Some(window);
            アプリ.レンダラー = Some(レンダラー);
            アプリ.開発ui = Some(開発ui);
            アプリ.アニメーション = アニメーション;
            アプリ.布プリセット = 布プリセット;
        }
        Err(誤り) => {
            アプリ.起動時エラー = Some(誤り);
            event_loop.exit();
        }
    }
}
