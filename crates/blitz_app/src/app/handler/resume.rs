//! `resumed`が呼ばれたときの生成と格納の局面。呼ばれるのは起動時の1回だけであり、イベントごとに呼ばれる`window_event`とは
//! 呼び出し頻度も触れるフィールドも違う。担当するのは、ウィンドウとレンダラーの生成を頼み、返ってきた一式をアプリのフィールドへ
//! 収め、束ごとの台帳へ起動時シーンを登録することである。生成そのものの手順は`window_setup`が持つ。

use winit::event_loop::ActiveEventLoop;

use crate::app::window_setup::{画面の作り方, 読み込む世界の材料, 起動時に組み上げた一式};
use crate::app::アプリ;

pub(super) fn 生成してアプリへ格納する(アプリ: &mut アプリ, event_loop: &ActiveEventLoop) {
    let 世界 = 読み込む世界の材料 {
        シーン: &アプリ.シーン,
        アセットの置き場: &アプリ.アセットの置き場,
        描画対象の並べ方: アプリ.描画対象の並べ方,
        大域平行移動: アプリ.大域ずらし量,
        チャンク一辺: アプリ
            .ストリーミング
            .配線を借りる()
            .map(super::super::streaming::ストリーミング配線::一辺),
        布モード: アプリ.布モード,
        基本刻み: アプリ.時間進行.基本刻み(),
    };
    let 作り方 = 画面の作り方 {
        粒子表示: アプリ.粒子表示,
        空中遠近合成: アプリ.空中遠近合成,
        開発ui初期有効: アプリ.開発ui初期有効,
        フレーム構成: アプリ.世界の描画構成.フレーム構成,
        実表示計測要求: crate::app::measurement_setup::実表示計測要求を決める(アプリ),
        影の一辺解像度: アプリ.天空.影の一辺解像度(),
        照明問い合わせ契約: アプリ.天空.照明問い合わせ契約(),
        自動露出の設定: アプリ.天空.自動露出の設定(),
        局所可視性の描画設定: アプリ.世界の描画構成.局所可視性の描画設定,
        時間再構成の描画設定: アプリ.世界の描画構成.時間再構成の描画設定,
    };
    let 組み上げ = crate::app::window_setup::ウィンドウとレンダラーを作る(
        event_loop,
        &世界,
        &作り方,
        &mut アプリ.ホットリローダー,
        &mut アプリ.ゲーム配線,
    );
    match 組み上げ {
        Ok(一式) => 格納する(アプリ, event_loop, 一式),
        Err(誤り) => {
            アプリ.起動時エラー = Some(誤り);
            event_loop.exit();
        }
    }
}

fn 格納する(アプリ: &mut アプリ, event_loop: &ActiveEventLoop, 一式: 起動時に組み上げた一式) {
    let 起動時に組み上げた一式 {
        window,
        mut レンダラー,
        画面へ重ねるui,
        アニメーション,
        布プリセット,
        布の参照比較,
        登録一式,
        遠景,
        地表の層のタイル,
    } = 一式;
    // 起動時シーンをディスクから読んだのはこの1回である。
    アプリ.シーン読込計数.読み込んだ(アプリ.現在フレーム);
    crate::reports::composition::ディスクリプタ索引上限を表示する(レンダラー.ディスクリプタ索引上限を取得する());
    if let Some(状況) = crate::app::measurement_setup::レンダラーの計測を有効にする(&mut レンダラー, アプリ) {
        println!("実表示時刻計測: {}", 状況.名称());
    }
    let 注入 = アプリ
        .読み戻し検収
        .遠方環境の検収条件
        .map(|条件| 条件.レンダラーへ注入する(&mut レンダラー));
    if let Some(Err(誤り)) = 注入 {
        アプリ.起動時エラー = Some(crate::error::起動エラー::from(誤り));
        event_loop.exit();
        return;
    }
    // 距離区分の分け方はカタログを読んで初めて決まる。最初のフレームより前で確定させる。
    アプリ.天空.距離区分の分け方を確定する(遠景.is_some());
    if let Err(誤り) = アプリ.永続束.起動時に登録する(
        &mut レンダラー,
        &mut アプリ.可視判定,
        &mut アプリ.プリミティブ描画項目台帳,
        登録一式,
        遠景,
    ) {
        アプリ.起動時エラー = Some(誤り);
        event_loop.exit();
        return;
    }
    アプリ.window = Some(window);
    アプリ.レンダラー = Some(レンダラー);
    アプリ.画面へ重ねるui = Some(画面へ重ねるui);
    アプリ.アニメーション = アニメーション;
    アプリ.布プリセット = 布プリセット;
    アプリ.布の参照比較 = 布の参照比較;
    アプリ.地表の層のタイル = 地表の層のタイル;
}
