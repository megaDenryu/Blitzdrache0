//! `resumed`が呼ばれたときの生成と格納の局面。呼ばれるのは起動時の1回だけであり、イベントごとに呼ばれる`window_event`とは
//! 呼び出し頻度も触れるフィールドも違う。担当するのは、ウィンドウとレンダラーの生成を頼み、返ってきた一式をアプリのフィールドへ
//! 収め、描画束の台帳へ起動時シーンを登録することである。生成そのものの手順は`window_setup`が持つ。
//!
//! 1回だけであることは、起動時に一度だけ使う設定を`take`で消費することが決める。2度目の`resumed`では
//! 設定が`None`であり、この局面は何もせずに戻る。この1回性を決めているのは設定の消費であり、winitの`resumed`が1回であることではない。
//! ゲーム世界の一回限りの初期化と、ウィンドウとサーフェスの据え付けを別の時間意味として分ける設計は Issue #145 が持つ。

use winit::event_loop::ActiveEventLoop;

use crate::app::screen_installation::画面の据え付け;
use crate::app::window_setup::{画面の作り方, 読み込む世界の材料, 起動時に組み上げた一式};
use crate::app::アプリ;

pub(super) fn 生成してアプリへ格納する(アプリ: &mut アプリ, event_loop: &ActiveEventLoop) {
    let Some(設定) = アプリ.一度だけ使う設定.take() else {
        return;
    };
    let 世界 = 読み込む世界の材料 {
        シーン: 設定.シーン(),
        アセットの置き場: 設定.アセットの置き場(),
        描画対象の並べ方: アプリ.描画対象の並べ方,
        大域平行移動: アプリ.大域ずらし量,
        チャンク一辺: アプリ.資源の配線.チャンク一辺(),
        布モード: 設定.布モード(),
        基本刻み: アプリ.時間進行.基本刻み(),
    };
    let 作り方 = 画面の作り方 {
        粒子表示: 設定.粒子表示(),
        空中遠近合成: 設定.空中遠近合成(),
        開発ui初期有効: 設定.開発uiを起動時から表示するか(),
        フレーム構成: アプリ.世界の描画構成.フレーム構成,
        実表示計測要求: アプリ.検収の起動設定.報告要求().実表示計測要求(),
        影の一辺解像度: アプリ.天空.影の一辺解像度(),
        照明問い合わせ契約: アプリ.天空.照明問い合わせ契約(),
        自動露出の設定: アプリ.天空.自動露出の設定(),
        局所可視性の描画設定: アプリ.世界の描画構成.局所可視性の描画設定,
        時間再構成の描画設定: アプリ.世界の描画構成.時間再構成の描画設定,
    };
    let 組み上げ = crate::app::window_setup::ウィンドウとレンダラーを作る(event_loop, &世界, &作り方, アプリ.資源の配線.ホットリローダーを可変で借りる(), &mut アプリ.ゲーム配線);
    match 組み上げ {
        Ok(一式) => アプリ.組み上げた一式を据える(event_loop, 一式),
        Err(誤り) => {
            アプリ.起動時エラー = Some(誤り);
            event_loop.exit();
        }
    }
}

impl アプリ {
    /// 組み上がった一式を自分のフィールドへ収め、描画束の台帳へ起動時シーンと遠景を登録する。
    /// 途中で失敗したときは起動時エラーを預かってイベントループを閉じる。
    fn 組み上げた一式を据える(&mut self, event_loop: &ActiveEventLoop, 一式: 起動時に組み上げた一式) {
        let 起動時に組み上げた一式 {
            window,
            mut レンダラー,
            画面へ重ねるui,
            アニメーション,
            布プリセット,
            布の参照比較,
            登録一式,
            遠景,
            地表の層のタイル,
        } = 一式;
        // 起動時シーンをディスクから読んだのはこの1回である。
        self.検収の観測.ディスクから読んだことを数える(crate::app::time_step::フレーム番号::起動時の最初());
        crate::reports::composition::ディスクリプタ索引上限を表示する(レンダラー.ディスクリプタ索引上限を取得する());
        if let Some(状況) = self.検収の観測.レンダラーの計測を有効にする(&mut レンダラー, self.起動モード, self.検収の起動設定.報告要求()) {
            println!("実表示時刻計測: {}", 状況.名称());
        }
        let 注入 = self.検収の起動設定.読み戻し検収().遠方環境の検収条件.map(|条件| 条件.レンダラーへ注入する(&mut レンダラー));
        if let Some(Err(誤り)) = 注入 {
            self.起動時エラー = Some(crate::error::起動エラー::from(誤り));
            event_loop.exit();
            return;
        }
        // 距離区分の分け方はカタログを読んで初めて決まる。最初のフレームより前で確定させる。
        self.天空.距離区分の分け方を確定する(遠景.is_some());
        if let Err(誤り) = self.描画束の台帳.起動時に登録する(&mut レンダラー, 登録一式, 遠景, 地表の層のタイル) {
            self.起動時エラー = Some(誤り);
            event_loop.exit();
            return;
        }
        self.据え付け = Some(画面の据え付け::据える(レンダラー, 画面へ重ねるui, window));
        self.アニメーション = アニメーション;
        self.布の配線.起動時に据える(布プリセット, 布の参照比較);
    }
}
