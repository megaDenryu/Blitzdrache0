//! 視点の配線。カメラと視点の履歴は、1描画の視点を決めるという1つの責務を共有し、寿命も起動から終了までで同じであるため、
//! 1つの型が持つ。命令は、この描画の視点を求める・注視点へ追従する・この描画の視点へ更新する・遮蔽の判定の入力を組んで
//! 表示距離の指示を適用する・視点の履歴を記録する、である。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断11」。
//!
//! `大域ずらし量`はこの型が保持せず、命令ごとに値で受ける。起動時に決まる写せる定数であり、私有にすると取り出す口が生えるためである。
//! 遮蔽の判定そのものはゲーム配線が世界の形を尋ねて行うため、この型は判定の入力を組むことと指示を据えることだけを持つ。
//! 視点の組み立ては`frame_view`、前フレームの視点の記録は`view_history`が持つ。

mod frame_view;
mod view_history;

pub(in crate::app) use frame_view::カメラ大域位置を組み立てる;
pub(crate) use frame_view::フレーム視点;

use blitz_engine::{カメラ, カメラの操作意図};
use blitz_math::{ラジアン, ワールド, 位置, 大域ワールド位置, 秒};

use crate::error::起動エラー;
use crate::game::{この描画のカメラの入力, 表示距離の指示};
use view_history::視点の履歴;

pub(in crate::app) struct 視点の配線 {
    カメラ: カメラ,
    視点の履歴: 視点の履歴, // 前フレームのずらし無しビュー射影とそのときのカメラ大域原点。提示へ到達したフレームだけが書く
}

impl 視点の配線 {
    pub(in crate::app) fn 生成する(カメラ: カメラ) -> Self {
        Self {
            カメラ,
            視点の履歴: 視点の履歴::記録なしで生成する(),
        }
    }

    /// ゲームが供給する注視点(混ぜた足元の位置に目の高さを足した点)へカメラの注視点を移す。ヨー・ピッチ・距離には指を触れない。
    /// 位置が無い起動(`--game`の指定が無い)ではカメラは1度も触られない。
    ///
    /// 注視点は局所ワールド位置で持つ。大域ずらし量は局所位置へ後から足される量であるため、ここでは引いて渡す
    /// (`カメラ大域位置を組み立てる`がその足し算を行う)。
    pub(in crate::app) fn 注視点へ追従する(&mut self, 大域位置: Option<大域ワールド位置>, 大域ずらし量: 大域ワールド位置) {
        let Some(大域位置) = 大域位置 else {
            return;
        };
        match 大域位置.局所ワールド位置へ狭める(大域ずらし量) {
            Ok(注視点) => self.カメラ.注視点を据える(注視点),
            // 追従の対象がf32で表せない距離まで離れたら、カメラを黙って据え置かず破られた不変条件として止める。
            // 1本目の世界の広さでは到達しない(参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「第1段階の定義」)。
            Err(誤り) => panic!("カメラが追従する大域位置を局所ワールド位置へ狭められない: {誤り}"),
        }
    }

    /// そのフレームのカメラ操作の意図をカメラへ通す。追従を先に据えてから呼ぶと、マウス操作が追従後の注視点に対して効く。
    pub(in crate::app) fn この描画の視点へ更新する(&mut self, 意図: カメラの操作意図) {
        self.カメラ.更新する(意図);
    }

    /// 遮蔽の判定へ渡す、この描画のカメラの姿勢と進めた時間。注視点と理想視点は局所ワールド位置で持たれているため、大域ずらし量を足して大域位置にする。
    pub(in crate::app) fn この描画のカメラの入力を組む(&self, 大域ずらし量: 大域ワールド位置, 進めた時間: 秒) -> この描画のカメラの入力 {
        この描画のカメラの入力 {
            注視点: カメラ大域位置を組み立てる(self.カメラ.注視点(), 大域ずらし量),
            理想視点: カメラ大域位置を組み立てる(self.カメラ.理想の視点ワールド位置(), 大域ずらし量),
            理想距離: self.カメラ.理想距離(),
            表示距離の下限: カメラ::最小距離(),
            進めた時間,
        }
    }

    pub(in crate::app) fn 表示距離の指示を適用する(&mut self, 指示: 表示距離の指示) -> Result<(), 起動エラー> {
        match 指示 {
            表示距離の指示::カメラを触らない => Ok(()),
            表示距離の指示::据える(表示距離) => Ok(self.カメラ.表示距離を据える(表示距離)?),
        }
    }

    /// 提示へ到達したフレームだけが呼ぶ。見送られたフレームの視点を記録すると、次のフレームの動きベクトルと棄却が誤った前フレーム対応を使う。
    pub(in crate::app) fn 視点の履歴を記録する(&mut self, 視点情報: &フレーム視点) {
        self.視点の履歴.記録する(視点情報.ビュー射影の組.ずらし無し(), 視点情報.カメラ大域位置);
    }

    /// 前へ進む向きの元になるヨー。刻みを回す工程が、この描画のカメラ操作を反映する前に読む。
    pub(in crate::app) fn ヨー(&self) -> ラジアン {
        self.カメラ.ヨー()
    }

    pub(in crate::app) fn 視点ワールド位置(&self) -> 位置<ワールド> {
        self.カメラ.視点ワールド位置()
    }

    /// ストリーミングの位置決定がカメラの視点位置を読むために貸す。
    pub(in crate::app) fn カメラを見る(&self) -> &カメラ {
        &self.カメラ
    }

    /// 個体詳細段探査が注視点を前後させるために貸す。
    pub(in crate::app) fn カメラを可変で借りる(&mut self) -> &mut カメラ {
        &mut self.カメラ
    }
}
