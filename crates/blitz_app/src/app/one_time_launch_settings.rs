//! 起動時に一度だけ使う設定。起動引数から読んだまま実行中は変わらず、`resume`が1度だけ読んで
//! `読み込む世界の材料`と`画面の作り方`へ写した後は誰も読まない通過材料である。
//!
//! `アプリ`が`Option`で持ち`resume`が`take`するのは、消費済みであることを型で言うためである。
//! 消費した後に残しておくと、起動の途中でしか意味を持たない値を描画の工程が読めてしまう。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断11」。

use crate::cli::{布モード, 空中遠近合成指定, 粒子表示モード, 起動時シーン};
use crate::runtime_assets::実行時アセットの置き場;

pub(in crate::app) struct 起動時に一度だけ使う設定 {
    シーン: 起動時シーン,
    アセットの置き場: 実行時アセットの置き場,
    空中遠近合成: 空中遠近合成指定,
    粒子表示: 粒子表示モード,
    開発uiを起動時から表示するか: bool,
    布モード: 布モード,
}

impl 起動時に一度だけ使う設定 {
    pub(in crate::app) fn 生成する(
        シーン: 起動時シーン, アセットの置き場: 実行時アセットの置き場, 空中遠近合成: 空中遠近合成指定, 粒子表示: 粒子表示モード, 開発uiを起動時から表示するか: bool, 布モード: 布モード
    ) -> Self {
        Self {
            シーン,
            アセットの置き場,
            空中遠近合成,
            粒子表示,
            開発uiを起動時から表示するか,
            布モード,
        }
    }

    pub(in crate::app) fn シーン(&self) -> &起動時シーン {
        &self.シーン
    }

    pub(in crate::app) fn アセットの置き場(&self) -> &実行時アセットの置き場 {
        &self.アセットの置き場
    }

    pub(in crate::app) fn 空中遠近合成(&self) -> 空中遠近合成指定 {
        self.空中遠近合成
    }

    pub(in crate::app) fn 粒子表示(&self) -> 粒子表示モード {
        self.粒子表示
    }

    pub(in crate::app) fn 開発uiを起動時から表示するか(&self) -> bool {
        self.開発uiを起動時から表示するか
    }

    pub(in crate::app) fn 布モード(&self) -> 布モード {
        self.布モード
    }
}
