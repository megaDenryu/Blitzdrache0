//! 起動時に、要求された報告に対応するレンダラー側の計測だけを有効にする局面。呼ばれるのはレンダラーを据える直前の1回であり、
//! 毎フレームの記録とは呼び出し頻度が違う。触れるのは、どの計測が有効な実行かという自分の2つの`Option`の有無だけである。

use blitz_render::{レンダラー, 実表示計測状況};

use super::検収の観測;
use crate::app::frame_timing::{ウォームアップフレーム数, 標本容量};
use crate::app::report_requests::報告要求;
use crate::cli::起動モード;

impl 検収の観測 {
    /// 注意: 実表示計測はCPU区間計測と独立に切り替える。実表示計測は`vkWaitForPresentKHR`で描画ループを
    /// 止めるため、フレーム時間報告に相乗りさせると素の条件のフレーム間隔が二度と測れなくなる。
    /// 戻り値は実表示計測を有効にしたときだけ`Some`で、その対応状況を表す。
    pub(in crate::app) fn レンダラーの計測を有効にする(&self, レンダラー: &mut レンダラー, モード: 起動モード, 報告要求: &報告要求) -> Option<実表示計測状況> {
        let 標本容量 = 標本容量(モード);
        // 区間の内訳はレンダラーの同じ計測から出るため、フレーム時間報告と区間報告のどちらでも有効にする。
        if self.フレーム間隔計測.is_some() || self.可視個体の選別の計測.is_some() {
            レンダラー.cpu区間計測を有効にする(ウォームアップフレーム数, 標本容量);
        }
        // フレーム別の生値はGPU計測が在るときだけ始まる。始まらなかったことは終了時の報告が明示する。
        if 報告要求.gpu時間のフレーム別生値 {
            レンダラー.パス別gpu時間のフレーム別記録を始める();
        }
        if !報告要求.実表示時間 {
            return None;
        }
        Some(レンダラー.実表示計測を有効にする(ウォームアップフレーム数, 標本容量))
    }
}
