//! アプリがディスクから実行時シーンを読んだ回数の記録。起動時シーンの読込とホットリロードの再読込を数える。
//! チャンクストリーミングの読込はこの数に入らない。あちらは読込器が別の経路で読み、ストリーミング要約が別に数えるためである。
//!
//! この数を持つのは、LODの段や可視判定の結果が変わってもディスクI/Oが起きないことを実行の外から見るためである。
//! 全段は束の読込時にGPUへ載っており、段の選択はファイルにもGPU確保にも触れない
//! (参照: `_doc/設計/植生インスタンスと物量計測.md`「ストリーミング統合」)。
//!
//! 鍵を描画機会の番号でなく契機にするのは、この計器が分けたいのが「起動時か起動後か」であって「何番目の描画か」ではないためである。
//! 起動時の読込はまだ1回も描いていない時点で起きるため、描画機会の番号0として記録すると、0番の描画の途中に起きた再読込と区別できない。

/// 実行時シーンをディスクから読んだ契機。起動時の1回と、起動後の描画機会の途中に起きるホットリロードの再読込の2つである。
pub(in crate::app) enum シーン読込の契機 {
    起動時,
    起動後の描画機会,
}

#[derive(Default)]
pub(super) struct シーン読込計数 {
    総数: u64,
    起動後: u64, // 起動後の描画機会に起きた読込の数。起動時の読込は入らない
}

impl シーン読込計数 {
    /// 実行時シーンをディスクから読んだ直後に呼ぶ。
    pub(super) fn 読み込んだ(&mut self, 契機: シーン読込の契機) {
        self.総数 += 1;
        match 契機 {
            シーン読込の契機::起動時 => {}
            シーン読込の契機::起動後の描画機会 => self.起動後 += 1,
        }
    }

    pub(super) fn 総数(&self) -> u64 {
        self.総数
    }

    pub(super) fn 起動後(&self) -> u64 {
        self.起動後
    }
}
