//! 検収の起動設定。読み戻し検収の指定・フレームダンプ先・終了時の報告要求の3つは、起動引数から読んだまま実行中は
//! 変わらない材料であり、1つの型が持つ。命令は「この描画の検収の経路を選ぶ」という純粋な判定だけであり、
//! 据え付けにも観測にも触れない。判定と実行を分けるのは、6つに分かれた検収の経路のどれへ進むかが
//! フレーム番号・起動モード・自己操作・段差の走査の撮影の4つだけから決まり、実行の側は据え付けと観測だけを触ればよいためである。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断11」。
//!
//! 経路の型と、ダンプの経路の判定(書き出し先の名前の付け方を含む)は`route`と`dump_route`が持つ。

mod dump_route;
mod route;

pub(in crate::app) use route::{時間再構成の観測の局面, 検収の経路};

use super::report_requests::報告要求;
use super::time_of_day::撮影の有無;
use super::time_step::フレーム番号;
use crate::cli::{フレームダンプ指定, 読み戻し検収起動設定, 起動モード};
use crate::smoke::スモークアクション;

/// 時間再構成の観測を採るフレーム数。画素内ずらしの列の長さの2周ぶんであり、周期の全体を2度見る。
/// 列の長さの倍数に採るのは、定常状態が列の長さを周期とする周期軌道であり、周期の全体を跨がないとフレーム間差分の上限を見誤るためである。
const 時間再構成の観測フレーム数: u32 = 16;

pub(in crate::app) struct 検収の起動設定 {
    読み戻し検収: 読み戻し検収起動設定,   // 読み戻した画像をCPU正本と突き合わせる照合の指定一式
    フレームダンプ先: フレームダンプ指定, // どの画像をどのベース名で書き出すか
    報告要求: 報告要求,                   // 終了時にどの報告を出すか
}

impl 検収の起動設定 {
    pub(in crate::app) fn 生成する(読み戻し検収: 読み戻し検収起動設定, フレームダンプ先: フレームダンプ指定, 報告要求: 報告要求) -> Self {
        Self {
            読み戻し検収, フレームダンプ先, 報告要求
        }
    }

    pub(in crate::app) fn 読み戻し検収(&self) -> &読み戻し検収起動設定 {
        &self.読み戻し検収
    }

    pub(in crate::app) fn 報告要求(&self) -> &報告要求 {
        &self.報告要求
    }

    /// この描画をどの検収の経路へ通すかを決める。判定の順序は、局所可視性・動きベクトル・時間再構成の突き合わせ・
    /// 時間再構成の観測・ダンプ・通常であり、先に立った経路が勝つ。読み戻しを伴う経路が`--frames`の最終フレームだけを
    /// 対象にするのは、それより前のフレームでは大気と間接照明の焼き上げが進行中で、検収と無関係な要因が画面に残るためである。
    ///
    /// 前提: 局所可視性の検収とフレームダンプの同時指定は起動引数の解析が型付きの失敗で拒む
    /// (`crate::cli::local_visibility_settings::検収とフレームダンプの排他を確かめる`)。
    pub(in crate::app) fn この描画の検収の経路を選ぶ(&self, フレーム番号: フレーム番号, モード: 起動モード, 自己操作: スモークアクション, 撮影: 撮影の有無) -> 検収の経路 {
        let スモークのフレーム数 = match モード {
            起動モード::スモーク実行 { フレーム数 } => Some(フレーム数),
            起動モード::無期限実行 | 起動モード::ベンチ実行 { .. } | 起動モード::段差走査実行 { .. } => None,
        };
        let 差し替え前か = 自己操作 == スモークアクション::差し替え前ダンプ;
        let 最終フレームか = スモークのフレーム数.is_some_and(|フレーム数| フレーム番号.最後のフレームか(フレーム数)) && !差し替え前か;
        if let Some(形) = self.読み戻し検収.局所可視性の検収の形
            && 最終フレームか
        {
            return 検収の経路::局所可視性 { 形 };
        }
        if self.読み戻し検収.動きベクトルを報告するか && 最終フレームか {
            return 検収の経路::動きベクトル;
        }
        if self.読み戻し検収.時間再構成の合成入力を突き合わせるか && 最終フレームか {
            return 検収の経路::時間再構成の突き合わせ;
        }
        if let Some(フレーム数) = スモークのフレーム数
            && self.読み戻し検収.時間再構成を報告するか
            && !差し替え前か
            && フレーム番号.最後の何フレームかに入るか(フレーム数, 時間再構成の観測フレーム数)
        {
            let 局面 = if フレーム番号.最後のフレームか(フレーム数) {
                時間再構成の観測の局面::無効化直後
            } else {
                時間再構成の観測の局面::フレーム間差分
            };
            return 検収の経路::時間再構成の観測 { 局面 };
        }
        self.ダンプの経路を選ぶ(フレーム番号, スモークのフレーム数, 自己操作, 撮影).unwrap_or(検収の経路::通常)
    }
}
