//! 布の毎フレーム入力(判断53・54)。カプセルはFoxの胴体近似1本(レスト姿勢の目視合わせ)。
//! 掴む介入: マウス右押下中、布の下端角の粒子をカーソル位置から写した目標へ毎フレーム固定し、
//! 離した最初のフレームで解放する(掴み状態バッファを持たない設計。判断54の補記どおり)。

use blitz_render::布フレーム入力;
use blitz_sim::介入;

use super::アプリ;

const カプセル端点A: [f32; 3] = [0.0, 45.0, -45.0];
const カプセル端点B: [f32; 3] = [0.0, 55.0, 45.0];
const カプセル半径: f32 = 22.0;

/// 掴み対象は布の下端行の左端(上端行はアタッチ済みで逆質量0のため掴めない)。
const 掴み粒子添字: u32 = (super::cloth_setup::一辺粒子数 - 1) * super::cloth_setup::一辺粒子数;

impl アプリ {
    pub(super) fn 布フレーム入力を作る(&mut self) -> Option<布フレーム入力> {
        if !self.布有効 {
            return None;
        }
        let 介入一覧 = self.掴み介入を作る();
        let 介入件数 = u32::try_from(介入一覧.len()).unwrap_or_else(|_| panic!("介入件数がu32に収まらない"));
        Some(布フレーム入力 {
            カプセル端点a: カプセル端点A,
            カプセル端点b: カプセル端点B,
            カプセル半径,
            介入バイト列: blitz_sim::バイト列にする(&介入一覧),
            介入件数,
        })
    }

    fn 掴み介入を作る(&mut self) -> Vec<介入> {
        let 掴み = self.入力状態.掴み操作().zip(self.window.as_ref().map(|w| w.inner_size()));
        match 掴み {
            Some(((px, py), 寸法)) => {
                self.掴み中だった = true;
                vec![介入::掴む { 粒子添字: 掴み粒子添字, 目標位置: 目標位置へ写す(px, py, 寸法.width, 寸法.height) }]
            }
            None if self.掴み中だった => {
                self.掴み中だった = false;
                vec![介入::離す { 粒子添字: 掴み粒子添字 }]
            }
            None => Vec::new(),
        }
    }
}

/// カーソル位置(物理px)を布の届くワールド範囲へ写す。foxシーンの初期構図
/// (カメラは+X軸上・ヨー90度で原点注視。画面右=ワールド-Z、画面上=ワールド+Y)専用の簡易写像で、
/// レイキャストは導入しない(判断53の最小実装)。
fn 目標位置へ写す(px: f32, py: f32, 幅: u32, 高さ: u32) -> [f32; 3] {
    let 幅f = 実数へ(幅);
    let 高さf = 実数へ(高さ);
    let x_ndc = (px / 幅f) * 2.0 - 1.0;
    let y_ndc = 1.0 - (py / 高さf) * 2.0;
    [0.0, 50.0 + y_ndc * 70.0, -x_ndc * 110.0]
}

/// 前提: ウィンドウ寸法は実運用で65535を超えない(draw_commandsのu16経由変換と同じ根拠)。
fn 実数へ(値: u32) -> f32 {
    f32::from(u16::try_from(値).unwrap_or_else(|_| panic!("ウィンドウ寸法がu16に収まらない: {値}")))
}
