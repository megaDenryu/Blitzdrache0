//! 布の毎フレーム入力(判断53・54)。カプセルはFoxの胴体近似1本(レスト姿勢の目視合わせ)。
//! 掴む介入(マウス操作)はM9第2段で追加する。現状は介入なし(落下+アタッチ追従のみ)。

use blitz_render::布フレーム入力;

use super::アプリ;

const カプセル端点A: [f32; 3] = [0.0, 45.0, -45.0];
const カプセル端点B: [f32; 3] = [0.0, 55.0, 45.0];
const カプセル半径: f32 = 22.0;

impl アプリ {
    pub(super) fn 布フレーム入力を作る(&self) -> Option<布フレーム入力> {
        if !self.布有効 {
            return None;
        }
        Some(布フレーム入力 {
            カプセル端点a: カプセル端点A,
            カプセル端点b: カプセル端点B,
            カプセル半径,
            介入バイト列: Vec::new(),
            介入件数: 0,
        })
    }
}
