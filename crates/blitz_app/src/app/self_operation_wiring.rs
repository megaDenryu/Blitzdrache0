//! 自己操作の配線。`--frames`のスモーク実行と`--lod-probe-step`の個体詳細段探査は、アプリが自分でウィンドウとカメラを
//! 動かして決定的な絵を作るという1つの責務を共有するため、1つの型が持つ。どちらも実行時の人の操作を1つも読まず、
//! フレーム番号だけから何をするかを決める。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断11」。
//!
//! ウィンドウとカメラをこの型が保持せず命令ごとに引数で受けるのは、どちらも別の階層(画面の据え付け・視点)が所有するためである。
//! ウィンドウへの適用とカメラへの適用が別の命令なのは、1描画の工程の中で適用する地点が違うためである。
//! ウィンドウは入力の確定より前に(最小化と寸法の変更を同じフレームの描画から効かせるため)、カメラはカメラ操作の直後に
//! (探査のずれをそのフレームのマウス操作の後へ載せるため)適用する。

mod lod_probe;

use winit::window::Window;

use blitz_engine::カメラ;

use super::time_step::フレーム番号;
use crate::cli::起動設定;
use crate::error::起動エラー;
use crate::smoke::{スモークアクション, スモーク実行};
use lod_probe::個体詳細段探査;

pub(in crate::app) struct 自己操作の配線 {
    スモーク実行: Option<スモーク実行>,     // `--frames`で起動したときだけ`Some`
    個体詳細段探査: Option<個体詳細段探査>, // `--lod-probe-step`指定時だけ`Some`
}

impl 自己操作の配線 {
    pub(in crate::app) fn 起動設定から作る(設定: &起動設定) -> Self {
        Self {
            スモーク実行: スモーク実行::起動設定から作る(設定),
            個体詳細段探査: 個体詳細段探査::生成する(設定.個体詳細段探査刻み),
        }
    }

    /// そのフレームの自己操作。`--frames`以外の起動はスモーク実行を持たないため、自己操作を1つも踏まない通常描画になる。
    /// 番号を生値へ戻すのは、スモークの計画が番号を総フレーム数との算術で使うためであり、この配線のこの1箇所だけである。
    pub(in crate::app) fn この描画の自己操作を決める(&self, フレーム番号: フレーム番号) -> スモークアクション {
        self.スモーク実行.as_ref().map_or(スモークアクション::通常描画, |実行| 実行.このフレームの動作を決める(フレーム番号.境界用の生値()))
    }

    /// 決めた自己操作のうちウィンドウを動かすもの(寸法の変更・最小化・復帰)を適用する。
    pub(in crate::app) fn ウィンドウへ適用する(&self, window: &Window, アクション: スモークアクション) {
        if let Some(実行) = &self.スモーク実行 {
            実行.ウィンドウへ自己操作を適用する(window, アクション);
        }
    }

    /// 探査を持つ起動なら、奇数フレームで刻みぶん奥へ、偶数フレームで元へカメラの注視点を動かす。
    pub(in crate::app) fn 探査をカメラへ適用する(&mut self, カメラ: &mut カメラ, フレーム番号: フレーム番号) {
        if let Some(探査) = &mut self.個体詳細段探査 {
            探査.適用する(カメラ, フレーム番号);
        }
    }

    /// 決めた自己操作のうちシェーダーまたはアセットの書き換えを適用する。
    pub(in crate::app) fn 書き換えを適用する(&self, アクション: スモークアクション) -> Result<(), 起動エラー> {
        self.スモーク実行.as_ref().map_or(Ok(()), |実行| 実行.書き換えを適用する(アクション))
    }
}
