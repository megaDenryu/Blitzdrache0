//! 常駐する束をレンダラーと2つの台帳へ据える工程。起動時の1回と、ホットリロードで起動時シーンを読み直したときの
//! 1回とを、別のメソッドとして持つ。
//!
//! 2つに分けるのは、遠景をレンダラーへ追加するのが起動時の1回だけだからである。ホットリロードは預かってある遠景を
//! 描画入力へ写し直して台帳へ据え直すだけであり、GPUへ触らない。1つのメソッドで両方を担うと、ホットリロードの側にも
//! 失敗しうる署名が残り、「レンダラーのシーンは新しく台帳は旧のまま」という混ざった状態へ至る経路が型の上に残る。
//! 呼び出し側の並び順でなく、メソッドの分かれ方でその経路を無くす。

use blitz_render::{レンダラー, 描画束ID};

use super::{プリミティブ描画項目台帳, 可視判定配線, 束の描画入力, 束の登録一式, 永続束の状態, 遠景の束ID};
use crate::error::起動エラー;

impl 永続束の状態 {
    /// 起動時に1度だけ、遠景をレンダラーへ追加してから2つの台帳を据える。追加はGPU側の確保を伴うため失敗しうる。
    /// 注意: 台帳の全解除は登録が成り立つと分かってから行う。先に解除すると、レンダラーへの追加が失敗した実行が
    /// 空の台帳のまま走り続け、絵から描画対象が丸ごと消える。旗で1度に限るのは、窓の作り直しでこの経路を
    /// 2度通っても同じ束IDが2度追加されないようにするためである。
    pub(super) fn 起動時に遠景を登録して束を据える(
        &mut self,
        レンダラー: &mut レンダラー,
        可視判定: &mut 可視判定配線,
        項目台帳: &mut プリミティブ描画項目台帳,
        登録一式: 束の登録一式,
        遠景: Option<束の描画入力>,
    ) -> Result<(), 起動エラー> {
        if let Some(遠景) = &遠景
            && !self.遠景をレンダラーへ登録済み
        {
            レンダラー.影方針つき描画束を追加する(遠景の束ID, &遠景.描画シーン, self.遠景の影方針)?;
            self.遠景をレンダラーへ登録済み = true;
        }
        self.台帳の2つの束を登録し直す(可視判定, 項目台帳, 登録一式, 遠景);
        Ok(())
    }

    /// ホットリロードで起動時シーンを読み直したときに、レンダラーへ登録済みの遠景のまま2つの台帳を据え直す。
    /// レンダラーを受け取らないことが、この経路がGPUへ触らず失敗しないことを表す。
    pub(in crate::app) fn 登録済みの遠景のまま束を据え直す(
        &mut self, 可視判定: &mut 可視判定配線, 項目台帳: &mut プリミティブ描画項目台帳, 登録一式: 束の登録一式, 遠景: Option<束の描画入力>
    ) {
        if 遠景.is_some() && !self.遠景をレンダラーへ登録済み {
            panic!("遠景を預かっているのにレンダラーへ登録済みでない(遠景シーンを預かる経路は起動時の登録だけであり、預かったなら同じ呼び出しでレンダラーへ登録されている)");
        }
        self.台帳の2つの束を登録し直す(可視判定, 項目台帳, 登録一式, 遠景);
    }

    /// 台帳を全解除してから起動時シーンの束と遠景の束を登録し直す。2つの経路が共有する後半である。
    fn 台帳の2つの束を登録し直す(&mut self, 可視判定: &mut 可視判定配線, 項目台帳: &mut プリミティブ描画項目台帳, 登録一式: 束の登録一式, 遠景: Option<束の描画入力>) {
        可視判定.全束を解除する();
        項目台帳.全束を解除する();
        台帳へ登録する(可視判定, 項目台帳, crate::app::scene_load::起動時シーンの束ID, 登録一式);
        if let Some(遠景) = 遠景 {
            台帳へ登録する(可視判定, 項目台帳, 遠景の束ID, 遠景.登録一式);
        }
    }
}

fn 台帳へ登録する(可視判定: &mut 可視判定配線, 項目台帳: &mut プリミティブ描画項目台帳, 束id: 描画束ID, 登録: 束の登録一式) {
    可視判定.束を登録する(束id, 登録.可視材料一覧);
    項目台帳.束を登録する(束id, 登録.プリミティブ描画項目一覧);
}
