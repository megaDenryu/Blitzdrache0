//! 常駐する束をレンダラーと2つの台帳へ据える工程。受け取るのはレンダラーと2つの台帳と束の登録一式、
//! 返すのは据えられたかどうかである。
//!
//! 起動時の1回とホットリロードの再登録が同じ工程を通る。どちらも「遠景をレンダラーへ1度だけ追加し、
//! 台帳を解除してから2つの束を登録し直す」という同じ手順であり、違うのは描画入力の出どころだけである。

use blitz_render::{レンダラー, 描画束ID};

use super::{プリミティブ描画項目台帳, 可視判定配線, 束の描画入力, 束の登録一式, 永続束の状態, 遠景の束ID};
use crate::error::起動エラー;

impl 永続束の状態 {
    /// 注意: 台帳の全解除は登録が成り立つと分かってから行う。先に解除すると、レンダラーへの追加が失敗した実行が
    /// 空の台帳のまま走り続け、絵から描画対象が丸ごと消える。遠景の追加はこの型が旗で1度に限っているため、
    /// 解除を後回しにしても同じ束IDが2度追加されることはない。
    pub(super) fn 束を据える(
        &mut self,
        レンダラー: &mut レンダラー,
        可視判定: &mut 可視判定配線,
        項目台帳: &mut プリミティブ描画項目台帳,
        起動時: 束の登録一式,
        遠景: Option<束の描画入力>,
    ) -> Result<(), 起動エラー> {
        if let Some(遠景) = &遠景
            && !self.遠景をレンダラーへ登録済み
        {
            レンダラー.影方針つき描画束を追加する(遠景の束ID, &遠景.描画シーン, self.遠景の影方針)?;
            self.遠景をレンダラーへ登録済み = true;
        }
        可視判定.全束を解除する();
        項目台帳.全束を解除する();
        台帳へ登録する(可視判定, 項目台帳, crate::app::scene_load::起動時シーンの束ID, 起動時);
        if let Some(遠景) = 遠景 {
            台帳へ登録する(可視判定, 項目台帳, 遠景の束ID, 遠景.登録一式);
        }
        Ok(())
    }
}

fn 台帳へ登録する(
    可視判定: &mut 可視判定配線, 項目台帳: &mut プリミティブ描画項目台帳, 束id: 描画束ID, 登録: 束の登録一式
) {
    可視判定.束を登録する(束id, 登録.可視材料一覧);
    項目台帳.束を登録する(束id, 登録.プリミティブ描画項目一覧);
}
