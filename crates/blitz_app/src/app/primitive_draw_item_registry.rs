//! 束の追加と解除で出入りするプリミティブ描画項目の台帳。触れるのは束IDとプリミティブ描画項目一覧の対応だけであり、毎フレームの走査も判定も行わない。
//! プリミティブ描画項目は束の読込時に一度だけ組み立て、束の解除まで同じ器を持ち続ける。中身が静的であり、毎フレームの確保も組み立て直しも要らないためである。
//! 読み手はまだ無い。プリミティブ別の描画発行(マルチマテリアルの段C)がこの台帳からプリミティブ描画項目を読んでレンダラーへ渡す。
//! 注意: 1つの束のプリミティブ描画項目は必ずまとめて入り、まとめて出る。レンダラーが描かなくなった束のプリミティブ描画項目が残ると、存在しない描画対象の発行を作る。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「段階導入」

use blitz_engine::primitive_draw_item::プリミティブ描画項目一覧;
use blitz_render::描画束ID;

#[derive(Default)]
pub(super) struct プリミティブ描画項目台帳 {
    束別一覧: Vec<(描画束ID, プリミティブ描画項目一覧)>,
}

impl プリミティブ描画項目台帳 {
    /// 描画束をレンダラーへ追加した直後に呼ぶ。同じ束IDの登録が残っていれば先に捨て、束の中身が二重に並ばないようにする。
    pub(super) fn 束を登録する(&mut self, 束id: 描画束ID, プリミティブ描画項目: プリミティブ描画項目一覧) {
        self.束を解除する(束id);
        self.束別一覧.push((束id, プリミティブ描画項目));
    }

    /// 描画束の解除を予約した時点で呼ぶ。可視材料と同じ契機で消すのは、2つが同じ束IDで対になるためである。
    pub(super) fn 束を解除する(&mut self, 束id: 描画束ID) {
        self.束別一覧.retain(|(登録済みid, _)| *登録済みid != 束id);
    }

    /// シーン差し替えは全束を作り直すため、プリミティブ描画項目も全部捨てる。
    pub(super) fn 全束を解除する(&mut self) {
        self.束別一覧.clear();
    }

    /// その束のプリミティブ描画項目。登録されていなければ`None`。段Cのプリミティブ別の描画発行がこの口から読み、段Cがこの`cfg(test)`を外す。
    /// 段Bの時点で本番の読み手が居ないため検査からだけ呼ぶ。閉じずに残すと未使用の警告を止めるlint緩和が要り、規約がそれを禁じている。
    /// 走査が線形なのは、件数が常駐するチャンクの数であり、束の追加と解除と同じ桁に収まるためである。
    #[cfg(test)]
    pub(super) fn 束のプリミティブ描画項目(&self, 束id: 描画束ID) -> Option<&プリミティブ描画項目一覧> {
        self.束別一覧.iter().find(|(登録済みid, _)| *登録済みid == 束id).map(|(_, 一覧)| 一覧)
    }
}
