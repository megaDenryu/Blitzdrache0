//! 布素材の構築(判断52)。blitz_simの布データをGPU境界のバイト列へ変換する。
//! アタッチ先の選択は`attach`にある。数値はFoxのスケール(1単位約1cm)前提。

mod attach;

use blitz_render::{布定数, 布素材};

use crate::error::起動エラー;

pub(super) const 一辺粒子数: u32 = 32;
const マント間隔: f32 = 3.2;
const 吊るし間隔: f32 = 0.05;
const 総質量: f32 = 4.0;

/// 掴み介入のカーソル→ワールド写像: 目標 = 中心 + 横基底*x_ndc + 縦基底*y_ndc(判断53の簡易写像)。
pub(super) struct 掴み写像 {
    pub(super) 中心: [f32; 3],
    pub(super) 横基底: [f32; 3],
    pub(super) 縦基底: [f32; 3],
}

/// 布シナリオごとの実行時パラメータ(判断56)。カプセルNoneはキャラ衝突なし。
pub(super) struct 布プリセット {
    pub(super) カプセル: Option<([f32; 3], [f32; 3], f32)>,
    pub(super) 掴み: 掴み写像,
}

/// 吊るし布(判断56の既定検証シナリオ): 上端行を空中に固定した布が正対カメラの前(quad構図)に垂れる。
/// スキン・アタッチ・カプセルを使わず、掴む/離す/床接触を最小の変数で見せる。寸法はquadスケール(約1m)。
pub(super) fn 吊るし布を構築する() -> Result<(布素材, 布プリセット), 起動エラー> {
    let 仕様 = blitz_sim::布仕様::生成する(一辺粒子数, 吊るし間隔, 総質量, [-0.775, 1.5, 0.4])?;
    let mut データ = blitz_sim::布を生成する(&仕様)?;
    for &添字 in &データ.上端行の粒子添字一覧.clone() {
        データ.粒子一覧[添字をusizeへ(添字)].逆質量 = 0.0;
    }
    let 定数 = 布定数 {
        重力: [0.0, -9.8, 0.0],
        粒子間隔: 吊るし間隔,
        グリッド原点: [-0.8, -0.05, -0.4],
        過緩和: 1.0,
        速度減衰: 0.99,
    };
    let 素材 = 布素材::生成する(
        blitz_sim::粒子バイト列にする(&データ),
        blitz_sim::隣接拘束バイト列にする(&データ),
        データ.描画用インデックス一覧,
        Vec::new(),
        一辺粒子数,
        定数,
    )?;
    let プリセット = 布プリセット {
        カプセル: None,
        掴み: 掴み写像 { 中心: [0.0, 0.75, 0.4], 横基底: [1.2, 0.0, 0.0], 縦基底: [0.0, 0.75, 0.0] },
    };
    Ok((素材, プリセット))
}

/// マント(fox限定): 布は32x32粒子・間隔3.2(幅約99)。重力はcm相当スケールの-980/s^2。
/// キャラ衝突はカプセル1本の近似で脚・首を覆えない(絵作りはドメイン表現層の課題としてM10以降)。
pub(super) fn マントを構築する(頂点一覧: &[blitz_render::頂点]) -> Result<(布素材, 布プリセット), 起動エラー> {
    let 仕様 = blitz_sim::布仕様::生成する(一辺粒子数, マント間隔, 総質量, [0.0, 0.0, 0.0])?;
    let mut データ = blitz_sim::布を生成する(&仕様)?;
    let アタッチ対応一覧 = attach::アタッチ先を選ぶ(頂点一覧, &データ.上端行の粒子添字一覧);
    attach::初期形状を整形する(&mut データ, 頂点一覧, &アタッチ対応一覧, マント間隔);
    let 定数 = 布定数 {
        重力: [0.0, -980.0, 0.0],
        粒子間隔: マント間隔,
        グリッド原点: [-51.0, 0.0, -51.0],
        過緩和: 1.0,
        速度減衰: 0.985,
    };
    let 素材 = 布素材::生成する(
        blitz_sim::粒子バイト列にする(&データ),
        blitz_sim::隣接拘束バイト列にする(&データ),
        データ.描画用インデックス一覧,
        アタッチ対応一覧,
        一辺粒子数,
        定数,
    )?;
    let プリセット = 布プリセット {
        カプセル: Some(([0.0, 45.0, -45.0], [0.0, 55.0, 45.0], 22.0)),
        掴み: 掴み写像 { 中心: [0.0, 50.0, 0.0], 横基底: [0.0, 0.0, -110.0], 縦基底: [0.0, 70.0, 0.0] },
    };
    Ok((素材, プリセット))
}

/// 前提: 帯数は上端行の粒子数(高々数百)でu16に収まる。
fn 帯数を実数へ(帯数: usize) -> f32 {
    f32::from(u16::try_from(帯数).unwrap_or_else(|_| panic!("帯数がu16に収まらない: {帯数}")))
}

fn 添字をusizeへ(値: u32) -> usize {
    usize::try_from(値).unwrap_or_else(|_| panic!("頂点添字がusizeに収まらない: {値}"))
}
