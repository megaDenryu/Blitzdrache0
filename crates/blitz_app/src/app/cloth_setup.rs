//! 布素材の構築(判断52)。blitz_simの布データをGPU境界のバイト列へ変換する。
//! アタッチ先の選択は`attach`にある。数値はFoxのスケール(1単位約1cm)前提。

mod attach;

use blitz_render::{布定数, 布素材};

use crate::error::起動エラー;

pub(super) const 一辺粒子数: u32 = 32;
const 粒子間隔: f32 = 3.2;
const 総質量: f32 = 4.0;

/// 布は32x32粒子・間隔3.2(幅約99。下端が床に届き「くちゃっ」が出る丈)。重力はcm相当スケールの-980/s^2。
/// 空間グリッドはセル寸法=間隔でFox周辺(±40)を覆う(範囲外はセルフコリジョン対象外)。
pub(super) fn 布素材を構築する(頂点一覧: &[blitz_render::頂点]) -> Result<布素材, 起動エラー> {
    let 仕様 = blitz_sim::布仕様::生成する(一辺粒子数, 粒子間隔, 総質量, [0.0, 0.0, 0.0])?;
    let mut データ = blitz_sim::布を生成する(&仕様)?;
    let アタッチ対応一覧 = attach::アタッチ先を選ぶ(頂点一覧, &データ.上端行の粒子添字一覧);
    初期形状を整形する(&mut データ, 頂点一覧, &アタッチ対応一覧);
    let 定数 = 布定数 {
        重力: [0.0, -980.0, 0.0],
        粒子間隔,
        グリッド原点: [-51.0, 0.0, -51.0],
        過緩和: 1.0,
        速度減衰: 0.985,
    };
    Ok(布素材::生成する(
        blitz_sim::粒子バイト列にする(&データ),
        blitz_sim::隣接拘束バイト列にする(&データ),
        データ.描画用インデックス一覧,
        アタッチ対応一覧,
        一辺粒子数,
        定数,
    )?)
}

/// 布の初期形状を「アタッチ先(Foxの背中のライン)から真下へ垂らしたマント」に整形する。
/// アタッチパスは毎フレーム上端を目標位置へ移すため、初期形状が離れていると
/// 1フレームで大移動が起き、距離拘束の巨大補正が伝播して布が発散する(実測で確認した)。
/// 初期形状をアタッチ後の想定形に一致させて発散を防ぐ。
fn 初期形状を整形する(データ: &mut blitz_sim::布データ, 頂点一覧: &[blitz_render::頂点], アタッチ対応一覧: &[[u32; 2]]) {
    let 一辺 = usize::try_from(一辺粒子数).unwrap_or_else(|_| panic!("一辺粒子数がusizeに収まらない"));
    for (列, 対応) in アタッチ対応一覧.iter().enumerate() {
        let 先 = 頂点一覧[添字をusizeへ(対応[1])].位置;
        for 行 in 0..一辺 {
            let 粒子添字 = 行 * 一辺 + 列;
            let 垂れ量 = 粒子間隔 * 帯数を実数へ(行);
            データ.粒子一覧[粒子添字].位置 = [先[0], 先[1] - 垂れ量, 先[2]];
        }
    }
}

/// 前提: 帯数は上端行の粒子数(高々数百)でu16に収まる。
fn 帯数を実数へ(帯数: usize) -> f32 {
    f32::from(u16::try_from(帯数).unwrap_or_else(|_| panic!("帯数がu16に収まらない: {帯数}")))
}

fn 添字をusizeへ(値: u32) -> usize {
    usize::try_from(値).unwrap_or_else(|_| panic!("頂点添字がusizeに収まらない: {値}"))
}
