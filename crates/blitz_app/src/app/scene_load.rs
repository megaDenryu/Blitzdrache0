//! シーンのカタログ構築・読込・レンダラー入力への変換。コンポジションルート
//! (起動時)とホットリロードの両方から使う共通処理。
//! マテリアル・頂点の個別変換は`convert`にある。

mod convert;

use std::path::Path;

use blitz_engine::{アセットID, カタログ, シーンを読み込む, シーンデータ};
use blitz_render::マテリアル素材;

use crate::error::起動エラー;

const 四角形識別子: &str = "quad";
const ヘルメット識別子: &str = "helmet";
const シャドウシーン識別子: &str = "shadow_scene";
const フォックス識別子: &str = "fox";

/// `アセットルート`配下のquad・DamagedHelmet・shadow_scene(判断37)・Fox(判断42)を登録したカタログを作る(判断7)。
pub(super) fn カタログを構築する(アセットルート: &Path) -> Result<カタログ, 起動エラー> {
    let mut カタログ = カタログ::空を作る();
    カタログ.登録する(アセットID::生成する(四角形識別子)?, アセットルート.join("smoke").join("quad.gltf"));
    カタログ.登録する(
        アセットID::生成する(ヘルメット識別子)?,
        アセットルート.join("samples").join("DamagedHelmet").join("DamagedHelmet.glb"),
    );
    カタログ.登録する(
        アセットID::生成する(シャドウシーン識別子)?,
        アセットルート.join("smoke").join("shadow_scene.gltf"),
    );
    カタログ.登録する(
        アセットID::生成する(フォックス識別子)?,
        アセットルート.join("samples").join("Fox").join("Fox.glb"),
    );
    Ok(カタログ)
}

/// シーンのスキン情報をレンダラーのスキンメッシュ素材へ変換する(判断44)。
/// スキンとスキン頂点属性の片方だけが存在するシーンは不整合として型付きエラーにする。
pub(super) fn スキン素材へ変換する(
    シーン: &シーンデータ
) -> Result<Option<blitz_render::スキンメッシュ素材>, 起動エラー> {
    match (&シーン.スキン, &シーン.先頭の描画対象().メッシュ().スキン頂点属性一覧) {
        (Some(スキン), Some(属性一覧)) => {
            let 変換済み = 属性一覧
                .iter()
                .map(|属性| blitz_render::スキン頂点属性 {
                    ジョイント: 属性.ジョイント.map(u32::from),
                    ウェイト: 属性.ウェイト,
                })
                .collect();
            Ok(Some(blitz_render::スキンメッシュ素材::生成する(
                変換済み,
                スキン.ジョイント一覧.len(),
            )?))
        }
        (None, None) => Ok(None),
        (Some(_), None) => Err(起動エラー::スキン整合性不正(
            "スキンはあるがスキン頂点属性が無い".to_string(),
        )),
        (None, Some(_)) => Err(起動エラー::スキン整合性不正(
            "スキン頂点属性はあるがスキンが無い".to_string(),
        )),
    }
}

/// カタログから`シーン名`を読み込み、レンダラー入力へ変換する。
pub(super) fn シーンを読み込んで変換する(
    カタログ: &カタログ,
    シーン名: &str,
) -> Result<(シーンデータ, Vec<blitz_render::頂点>, Vec<u32>, マテリアル素材), 起動エラー> {
    let id = アセットID::生成する(シーン名)?;
    let シーン = シーンを読み込む(カタログ, &id).map_err(起動エラー::シーン読込失敗)?;
    let (頂点一覧, インデックス一覧, マテリアル) = シーンをレンダラー入力に変換する(&シーン)?;
    Ok((シーン, 頂点一覧, インデックス一覧, マテリアル))
}

/// 既に読み込み済みの`シーンデータ`をレンダラー入力へ変換する(ホットリロード再読込用)。
pub(super) fn シーンをレンダラー入力に変換する(
    シーン: &シーンデータ,
) -> Result<(Vec<blitz_render::頂点>, Vec<u32>, マテリアル素材), 起動エラー> {
    let 描画対象 = シーン.先頭の描画対象();
    let 頂点一覧 = 描画対象.メッシュ().頂点一覧.iter().map(convert::頂点変換する).collect();
    let インデックス一覧 = 描画対象.メッシュ().インデックス一覧.clone();
    let マテリアル = convert::マテリアルを変換する(描画対象.マテリアル())?;
    Ok((頂点一覧, インデックス一覧, マテリアル))
}
