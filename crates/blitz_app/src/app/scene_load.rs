//! シーンのカタログ構築・読込・レンダラー入力への変換。コンポジションルート
//! (起動時)とホットリロードの両方から使う共通処理。
//! マテリアル・頂点の個別変換は`convert`にある。

mod convert;
mod render_input;

use std::path::Path;

use blitz_engine::{
    アセットID, カタログ, シーンデータ, チャンク目録, 実行時カタログを読み込む, 実行時シーンを読み込む, 実行時チャンク目録を読み込む,
};
use blitz_math::大域ワールド位置;

use crate::error::起動エラー;

/// `アセットルート`配下の版付きカタログを読み、生成物の相対パスを解決する。
pub(super) fn カタログを構築する(アセットルート: &Path) -> Result<カタログ, 起動エラー> {
    実行時カタログを読み込む(&アセットルート.join("catalog.blitzcatalog")).map_err(起動エラー::カタログ読込失敗)
}

/// `アセットルート`配下の版付きチャンク目録を読み、座標からアセットIDへの解決表を作る。
pub(crate) fn チャンク目録を構築する(アセットルート: &Path) -> Result<チャンク目録, 起動エラー> {
    実行時チャンク目録を読み込む(&アセットルート.join("chunk_directory.blitzchunks")).map_err(起動エラー::チャンク目録読込失敗)
}

/// シーンのスキン情報をレンダラーのスキンメッシュ素材へ変換する(判断44)。
/// スキンとスキン頂点属性の片方だけが存在するシーンは不整合として型付きエラーにする。
pub(super) fn スキン素材へ変換する(
    シーン: &シーンデータ
) -> Result<Option<blitz_render::スキンメッシュ素材>, 起動エラー> {
    match (&シーン.スキン, &シーン.先頭の描画対象().メッシュ().スキン頂点属性一覧) {
        (Some(スキン), Some(属性一覧)) => {
            let 変換済み = 属性一覧
                .iter()
                .map(|属性| blitz_render::スキン頂点属性 {
                    ジョイント: 属性.ジョイント.map(u32::from),
                    ウェイト: 属性.ウェイト,
                })
                .collect();
            Ok(Some(blitz_render::スキンメッシュ素材::生成する(
                変換済み,
                スキン.ジョイント一覧.len(),
            )?))
        }
        (None, None) => Ok(None),
        (Some(_), None) => Err(起動エラー::スキン整合性不正(
            "スキンはあるがスキン頂点属性が無い".to_string(),
        )),
        (None, Some(_)) => Err(起動エラー::スキン整合性不正(
            "スキン頂点属性はあるがスキンが無い".to_string(),
        )),
    }
}

/// カタログから`シーン名`を読み込み、レンダラー入力へ変換する。
pub(super) fn シーンを読み込んで変換する(
    カタログ: &カタログ,
    シーン名: &str,
    描画対象数: Option<crate::cli::描画対象数>,
    大域アンカー: 大域ワールド位置,
) -> Result<(シーンデータ, blitz_render::描画シーン素材), 起動エラー> {
    let id = アセットID::生成する(シーン名)?;
    let シーン = 実行時シーンを読み込む(カタログ, &id).map_err(起動エラー::シーン読込失敗)?;
    let 描画シーン = シーンをレンダラー入力に変換する(&シーン, 描画対象数, 大域アンカー)?;
    Ok((シーン, 描画シーン))
}

/// 既に読み込み済みの`シーンデータ`をレンダラー入力へ変換する(ホットリロード再読込用)。
/// `大域アンカー`はそのシーンが属するチャンクの大域原点であり、頂点はこのアンカーを基準にした局所座標として扱う。
pub(crate) fn シーンをレンダラー入力に変換する(
    シーン: &シーンデータ,
    描画対象数: Option<crate::cli::描画対象数>,
    大域アンカー: 大域ワールド位置,
) -> Result<blitz_render::描画シーン素材, 起動エラー> {
    render_input::変換する(シーン, 描画対象数, 大域アンカー)
}
