//! シーンのカタログ構築・読込・レンダラー入力への変換。コンポジションルート
//! (起動時)とホットリロードの両方から使う共通処理。

use std::path::Path;

use blitz_engine::{
    アセットID, カタログ, シーンデータ, シーンを読み込む, マテリアルデータ, 白テクスチャデータを作る,
    法線マップ既定テクスチャを作る,
};
use blitz_render::{テクスチャ用途, マテリアル素材};

use crate::error::起動エラー;

const 四角形識別子: &str = "quad";
const ヘルメット識別子: &str = "helmet";
const シャドウシーン識別子: &str = "shadow_scene";

/// `アセットルート`配下のquad・DamagedHelmet・shadow_scene(判断37)を登録したカタログを作る(判断7)。
pub(super) fn カタログを構築する(アセットルート: &Path) -> Result<カタログ, 起動エラー> {
    let mut カタログ = カタログ::空を作る();
    カタログ.登録する(
        アセットID::生成する(四角形識別子)?,
        アセットルート.join("smoke").join("quad.gltf"),
    );
    カタログ.登録する(
        アセットID::生成する(ヘルメット識別子)?,
        アセットルート.join("samples").join("DamagedHelmet").join("DamagedHelmet.glb"),
    );
    カタログ.登録する(
        アセットID::生成する(シャドウシーン識別子)?,
        アセットルート.join("smoke").join("shadow_scene.gltf"),
    );
    Ok(カタログ)
}

/// カタログから`シーン名`を読み込み、レンダラー入力へ変換する。
pub(super) fn シーンを読み込んで変換する(
    カタログ: &カタログ,
    シーン名: &str,
) -> Result<(シーンデータ, Vec<blitz_render::頂点>, Vec<u32>, マテリアル素材), 起動エラー> {
    let id = アセットID::生成する(シーン名)?;
    let シーン = シーンを読み込む(カタログ, &id).map_err(起動エラー::シーン読込失敗)?;
    let (頂点一覧, インデックス一覧, マテリアル) = シーンをレンダラー入力に変換する(&シーン)?;
    Ok((シーン, 頂点一覧, インデックス一覧, マテリアル))
}

/// 既に読み込み済みの`シーンデータ`をレンダラー入力へ変換する(ホットリロード再読込用)。
pub(super) fn シーンをレンダラー入力に変換する(
    シーン: &シーンデータ,
) -> Result<(Vec<blitz_render::頂点>, Vec<u32>, マテリアル素材), 起動エラー> {
    let 頂点一覧 = シーン.メッシュ.頂点一覧.iter().map(頂点変換する).collect();
    let インデックス一覧 = シーン.メッシュ.インデックス一覧.clone();
    let マテリアル = マテリアルを変換する(&シーン.マテリアル)?;
    Ok((頂点一覧, インデックス一覧, マテリアル))
}

/// 判断23: 無いテクスチャへ既定素材(白・MR白・既定法線)を明示適用してから
/// `マテリアル素材`を組み立てる(無言のデフォルト適用の禁止)。
fn マテリアルを変換する(データ: &マテリアルデータ) -> Result<マテリアル素材, 起動エラー> {
    let ベースカラー元 = データ.ベースカラー.clone().unwrap_or_else(白テクスチャデータを作る);
    let 金属粗さ元 = データ.金属粗さ.clone().unwrap_or_else(白テクスチャデータを作る);
    let 法線マップ元 = データ.法線マップ.clone().unwrap_or_else(法線マップ既定テクスチャを作る);

    let ベースカラー = blitz_render::テクスチャ素材::生成する(
        ベースカラー元.幅,
        ベースカラー元.高さ,
        ベースカラー元.rgba8,
        テクスチャ用途::色,
    )?;
    let 金属粗さ = blitz_render::テクスチャ素材::生成する(
        金属粗さ元.幅,
        金属粗さ元.高さ,
        金属粗さ元.rgba8,
        テクスチャ用途::線形データ,
    )?;
    let 法線マップ = blitz_render::テクスチャ素材::生成する(
        法線マップ元.幅,
        法線マップ元.高さ,
        法線マップ元.rgba8,
        テクスチャ用途::線形データ,
    )?;

    Ok(マテリアル素材::生成する(
        ベースカラー,
        金属粗さ,
        法線マップ,
        データ.ベースカラー係数,
        データ.金属度係数,
        データ.粗さ係数,
    )?)
}

fn 頂点変換する(属性: &blitz_engine::メッシュ頂点属性) -> blitz_render::頂点 {
    blitz_render::頂点 {
        位置: 属性.位置,
        法線: 属性.法線,
        接線: 属性.接線,
        uv: 属性.uv,
    }
}
