/// 起動時シーンはストリーミング対象でないため世界の原点チャンクに属する。
/// 参照: `_doc/計画/ユビキタス言語.md`「所有チャンク」
pub(super) const 起動時シーンの所有チャンク: チャンク座標 = チャンク座標::生成する(0, 0);

/// 起動時のシーンをレンダラーが持つときの描画束ID。
/// 注意: この番号はレンダラー側の`起動シーンの束ID`と同じ値でなければならない(参照: `crates/blitz_render/src/renderer/scene_draw_resources/create.rs`)。
pub(crate) const 起動時シーンの束ID: blitz_render::描画束ID = blitz_render::描画束ID::生成する(0);

/// 置き場の版付きチャンク目録を読み、座標からアセットIDへの解決表を作る。
pub(crate) fn チャンク目録を構築する(置き場: &実行時アセットの置き場) -> Result<チャンク目録, 起動エラー> {
    置き場.チャンク目録のファイル().読み込む().map_err(起動エラー::チャンク目録読込失敗)
}

/// シーンのスキン情報をレンダラーのスキンメッシュ素材へ変換する(判断44)。
/// スキンとスキン頂点属性の片方だけが存在するシーンは不整合として型付きエラーにする。
pub(super) fn スキン素材へ変換する(
    シーン: &シーンデータ
) -> Result<Option<blitz_render::スキンメッシュ素材>, 起動エラー> {
    match (&シーン.スキン, シーン.先頭の描画対象().形状().スキン頂点属性一覧()) {
        (Some(スキン), Some(属性一覧)) => {
            let 変換済み = 属性一覧
                .iter()
                .map(|属性| blitz_render::スキン頂点属性 {
                    ジョイント: 属性.ジョイント.map(u32::from),
                    ウェイト: 属性.ウェイト,
                })
                .collect();
            Ok(Some(blitz_render::スキンメッシュ素材::生成する(
                変換済み,
                スキン.ジョイント一覧.len(),
            )?))
        }
        (None, None) => Ok(None),
        (Some(_), None) => Err(起動エラー::スキン整合性不正(
            "スキンはあるがスキン頂点属性が無い".to_string(),
        )),
        (None, Some(_)) => Err(起動エラー::スキン整合性不正(
            "スキン頂点属性はあるがスキンが無い".to_string(),
        )),
    }
}

/// カタログから起動時シーンを読み込み、レンダラー入力へ変換する。
pub(super) fn シーンを読み込んで変換する(
    カタログ: &カタログ,
    安定id: &アセットID,
    並べ方: crate::cli::描画対象の並べ方,
    大域平行移動: 大域ワールド位置,
) -> Result<(シーンデータ, 束の描画入力), 起動エラー> {
    let シーン = 実行時シーンのファイル::カタログの安定idから作る(カタログ, 安定id)
        .ok_or_else(|| 実行時シーン読込エラー::カタログ未登録(安定id.clone()))
        .and_then(|ファイル| ファイル.読み込む())
        .map_err(起動エラー::シーン読込失敗)?;
    let 描画入力 = シーンをレンダラー入力に変換する(&シーン, 並べ方, 起動時シーンの所有チャンク, 大域平行移動)?;
    Ok((シーン, 描画入力))
}

/// 既に読み込み済みの`シーンデータ`をレンダラー入力へ変換する(ホットリロード再読込とチャンク束の追加で使う)。
/// `束座標`はそのシーンを載せる描画束のチャンク座標である。描画の基準原点はこの座標から導出し、シーン内の全描画対象がこの座標を所有チャンクに持つことを検証する。
/// `大域平行移動`は`--global-offset`が世界全体へ加える平行移動であり、導出した基準原点へ最後に合成する。
pub(crate) fn シーンをレンダラー入力に変換する(
    シーン: &シーンデータ,
    並べ方: crate::cli::描画対象の並べ方,
    束座標: チャンク座標,
    大域平行移動: 大域ワールド位置,
) -> Result<束の描画入力, 起動エラー> {
    render_input::変換する(シーン, 並べ方, 束座標, 大域平行移動)
}
