//! 生成台帳で公開が完了した実行時カタログ・チャンク目録・起動時シーンを1組として反映する局面。
//! 呼ばれるのはホットリローダーが再読込の成功を返した回だけであり、シェーダーの差し替えとは反映先も手順も違う。
//!
//! 反映は準備と反映の2段に分かれる。準備(`preparation`)は状態を1つも変えずに失敗しうる工程を全部終え、
//! 反映(ここ)は準備が揃えた材料を据える。反映で失敗しうるのは、事前に検証できないレンダラーのシーンの差し替えだけで
//! あり、それを先頭に置く。失敗したら何も変えずに型付きの結果で返す。台帳の据え直しは遠景を新しく登録しないため失敗せず
//! (`persistent_bundles/placement.rs`)、差し替えの後に失敗しうる工程は1つも残らない。
//! ゲーム世界へ効く3つ(地表の層のタイル・高さ場・ホットリローダーの世代)は全部の最後にまとめて据える。この順序により、GPU側が失敗したときにゲーム世界と
//! 世代は旧のままであり、ゲーム世界と描画世界が別の世代になる状態は生まれない(ゲーム実行基盤の設計正本が構造変更へ
//! 求める、工程境界での原子的な反映と同じ要求である)。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断11」

mod error;
mod preparation;
mod scene_preparation;
mod validation;

use super::hot_reload_check::ホットリロードの反映先;
use super::資源の配線;
use crate::hot_reload::公開済みの実行時アセット一式;
pub(super) use error::実行時アセット一式の反映エラー;
use preparation::反映準備;
use scene_preparation::{起動時シーンの反映準備, 起動時シーンの差し替え材料};

impl 資源の配線 {
    /// 失敗の選択肢は、何も変えていない準備の失敗と、レンダラーが差し替えを拒んだ反映の失敗を区別する。続けるかどうかは呼び出し側が決める。
    pub(super) fn 公開済みの実行時アセット一式を反映する(
        &mut self, 一式: 公開済みの実行時アセット一式, 反映先: ホットリロードの反映先<'_>
    ) -> Result<(), 実行時アセット一式の反映エラー> {
        let 準備 = 反映準備::状態を変えずに組む(&self.ストリーミング, &反映先, 一式)?;
        let 反映準備 {
            高さ場,
            地表の層のタイル,
            起動時シーン,
            チャンク目録,
            旧世界の束一覧,
            カタログ,
            公開完了印,
        } = 準備;
        let 起動時シーンの内容 = match 起動時シーン {
            起動時シーンの反映準備::同じ内容 { 内容 } => 内容,
            起動時シーンの反映準備::変更あり { 内容, 差し替え } => {
                let 起動時シーンの差し替え材料 { 描画シーン, 登録一式, 遠景 } = *差し替え;
                反映先.レンダラー.シーンを差し替える(描画シーン).map_err(実行時アセット一式の反映エラー::レンダラーのシーン差し替え失敗)?;
                反映先.描画束の台帳.起動時シーンと遠景を再登録する(登録一式, 遠景);
                内容
            }
        };
        if let Some(配線) = self.ストリーミング.配線を可変で借りる() {
            配線.チャンク目録と描画束を差し替える(チャンク目録, 旧世界の束一覧, &mut *反映先.レンダラー, &mut *反映先.描画束の台帳);
        }
        // ここから下がゲーム世界へ効く。上のどこで失敗しても、この3つは旧世代のままである。
        反映先.描画束の台帳.地表の層のタイルを据える(地表の層のタイル);
        反映先.世界実行.高さ場を据える(高さ場);
        self.ホットリローダー.実行時アセット一式を採用する(カタログ, 起動時シーンの内容, 公開完了印);
        Ok(())
    }
}
