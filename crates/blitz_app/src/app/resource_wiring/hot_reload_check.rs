//! ホットリローダーの確認結果(シェーダー再コンパイル・アセット再読込)をレンダラーと描画束の台帳へ反映する局面。
//! 実行時アセット一式の反映そのものは`asset_apply`が所有し、ここは結果の枝分かれだけを持つ。
//! 呼び出しタイミング: `frame`の`一フレーム実行する`の冒頭で、その回の入力確定より前に呼ぶ(差し替えを同じフレームの描画から効かせるため)。

use blitz_render::レンダラー;

use super::資源の配線;
use crate::app::draw_bundle_ledger::描画束の台帳;
use crate::app::screen_installation::画面の据え付け;
use crate::app::time_step::フレーム番号;
use crate::app::アプリ;
use crate::hot_reload::ホットリロード結果;

/// 契約別のシェーダー束でシーンのパイプライン表を交換できたときに1回だけ出す行。
const 差し替え成功の行: &str = "[hot-reload] 契約別のシェーダー束でシーンのパイプラインを差し替えた";

/// ホットリロードの反映が書き込む先。5つは毎回そろって渡り、どれか1つだけを渡す呼び出しが無いため1つの値で持つ。
pub(super) struct ホットリロードの反映先<'借用> {
    pub(super) レンダラー: &'借用 mut レンダラー,
    pub(super) 描画束の台帳: &'借用 mut 描画束の台帳,
    pub(super) ゲーム配線: &'借用 mut crate::game::ゲーム配線,
    pub(super) 描画対象の並べ方: crate::cli::描画対象の並べ方,
    pub(super) 大域ずらし量: blitz_math::大域ワールド位置,
}

/// ディスクから実行時シーンを読んだかどうか。読んだ回数を数えるのはアプリであり、この配線は数を持たない。
#[derive(PartialEq, Eq)]
pub(super) enum 実行時シーンをディスクから読んだか {
    読んでいない,
    読んだ,
}

impl 資源の配線 {
    pub(super) fn ホットリロードを確認する(&mut self, 反映先: ホットリロードの反映先<'_>) -> 実行時シーンをディスクから読んだか {
        let 結果 = self.ホットリローダー.確認する();
        // 再読込は成否によらずディスクを読む。読んだ事実をこの判定で呼び出し側へ伝える。
        let 読んだか = if matches!(結果, ホットリロード結果::アセット再読込成功 { .. } | ホットリロード結果::アセット再読込失敗 { .. }) {
            実行時シーンをディスクから読んだか::読んだ
        } else {
            実行時シーンをディスクから読んだか::読んでいない
        };
        match 結果 {
            ホットリロード結果::変化なし => {}
            ホットリロード結果::シェーダー再コンパイル成功 { シェーダー } => {
                match 反映先.レンダラー.シェーダーを差し替える(シェーダー) {
                    // 注意: この行の綴りは`cargo xtask shader-reload-draw`が数える。差し替えが1度も起きなかった実行を
                    // 「絵が変わらなかった」だけで通さないための計数であり、文面を変えるときは検収側も同時に直す。
                    Ok(()) => println!("{}", 差し替え成功の行),
                    Err(誤り) => eprintln!("[hot-reload] パイプライン差し替えに失敗した: {誤り}"),
                }
            }
            ホットリロード結果::シェーダー再コンパイル失敗 { 誤り } => {
                eprintln!("[hot-reload] シェーダーの再コンパイルに失敗した:\n{誤り}");
            }
            ホットリロード結果::アセット再読込成功 { 一式 } => {
                // ホットリロードは開発の道具であるため、反映できなくても実行は続ける。旧世界を保った理由をここで1度だけ出す。
                if let Err(誤り) = self.公開済みの実行時アセット一式を反映する(*一式, 反映先) {
                    eprintln!("[hot-reload] 実行時アセット一式を反映できなかった: {誤り}");
                }
            }
            ホットリロード結果::アセット再読込失敗 { 誤り } => {
                eprintln!("[hot-reload] アセットの再読込に失敗した:\n{誤り}");
            }
        }
        読んだか
    }
}

impl アプリ {
    /// 資源の配線へ書き込み先を渡して確認を頼み、ディスクを読んだ回数だけ自分が数える。
    pub(in crate::app) fn ホットリロードを確認する(&mut self, フレーム番号: フレーム番号) {
        let 反映先 = ホットリロードの反映先 {
            レンダラー: 画面の据え付け::描画の最中に借りる(&mut self.据え付け).レンダラーを借りる(),
            描画束の台帳: &mut self.描画束の台帳,
            ゲーム配線: &mut self.ゲーム配線,
            描画対象の並べ方: self.描画対象の並べ方,
            大域ずらし量: self.大域ずらし量,
        };
        if self.資源の配線.ホットリロードを確認する(反映先) == 実行時シーンをディスクから読んだか::読んだ {
            self.検収の観測.ディスクから読んだことを数える(フレーム番号);
        }
    }
}
