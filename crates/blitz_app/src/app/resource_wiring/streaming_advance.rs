//! ストリーミングを進める命令の入口。ホットリローダーが預かる実行時カタログを取り出し、ストリーミングの配線へ渡す。
//! 2つを1つの型が持つ理由がここに現れる。進行はカタログを読み、カタログの世代を決めるのはホットリローダーである。
//!
//! いつ呼ばれるか: 1描画に1度、カメラ更新の直後である。

use super::資源の配線;
use crate::app::screen_installation::画面の据え付け;
use crate::app::streaming::ストリーミング進行の材料;
use crate::app::time_step::フレーム番号;
use crate::app::アプリ;
use crate::error::起動エラー;

impl 資源の配線 {
    pub(super) fn ストリーミングを進める(&mut self, 材料: ストリーミング進行の材料<'_>) -> Result<(), 起動エラー> {
        let Some(配線) = self.ストリーミング.配線を可変で借りる() else {
            return Ok(());
        };
        let Some(カタログ) = self.ホットリローダー.カタログを参照する() else {
            return Err(起動エラー::ストリーミングカタログ未構築);
        };
        配線.この描画のストリーミングを進める(カタログ, 材料)
    }
}

impl アプリ {
    /// カメラ更新の直後に呼ぶ。ゲームを遊ばない起動の位置源はカメラの視点位置であり、必要集合の中心を確定した視点から決めるため、カメラより先に呼んではならない。
    ///
    /// 必要集合の中心は刻み境界の確定位置で決める。常駐するチャンクの集合はゲームが読む高さ場を決めるため、
    /// 混ぜた位置をここへ通すと、描画のためだけに作った値が次のゲーム更新の入力へ回り込む。
    pub(in crate::app) fn ストリーミングを進める(&mut self, フレーム番号: フレーム番号) -> Result<(), 起動エラー> {
        let 材料 = ストリーミング進行の材料 {
            レンダラー: 画面の据え付け::描画の最中に借りる(&mut self.据え付け).レンダラーを借りる(),
            描画束の台帳: &mut self.描画束の台帳,
            カメラ: &self.カメラ,
            プレイヤーの大域位置: self.ゲーム配線.刻み境界で確定したプレイヤーの大域位置(),
            大域ずらし量: self.大域ずらし量,
            フレーム番号,
        };
        self.資源の配線.ストリーミングを進める(材料)
    }
}
