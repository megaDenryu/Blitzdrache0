//! 公開済み一式のうち、状態を変えずに確定できるチャンク一辺・高さ場・地表の層のタイルを先に作る工程。
//! 受け取るのはストリーミングの有無と世界実行と公開済み一式だけであり、アプリの他の状態には触れない。

use super::error::実行時アセット一式の反映エラー;
use crate::app::scene_load::地表の層のタイル一式;
use crate::app::streaming::{ストリーミングの有無, ストリーミング配線};
use crate::hot_reload::公開済みの実行時アセット一式;
use crate::world_execution::世界実行;

pub(super) struct 検査を通った材料 {
    pub(super) 高さ場: crate::world_execution::contract::ゲーム用高さ場,
    pub(super) 一辺: Option<blitz_engine::チャンク一辺>,
    pub(super) 地表の層のタイル: 地表の層のタイル一式,
}

/// 3つのどれか1つでも作れなければ、この世代の一式を採用しない。
pub(super) fn 反映前の検査を通す(
    ストリーミング: &ストリーミングの有無, 世界実行: &世界実行, 一式: &公開済みの実行時アセット一式
) -> Result<検査を通った材料, 実行時アセット一式の反映エラー> {
    if let Some(配線) = ストリーミング.配線を借りる() {
        配線.チャンク目録の一辺を検査する(&一式.チャンク目録)?;
    }
    let 高さ場 = 世界実行.カタログから高さ場を読み込む(&一式.カタログ)?;
    let 地表の層のタイル = 地表の層のタイル一式::読み口から作る(&一式.地表層テクスチャ集).map_err(実行時アセット一式の反映エラー::地表の層のタイル変換失敗)?;
    Ok(検査を通った材料 {
        高さ場,
        一辺: ストリーミング.配線を借りる().map(ストリーミング配線::一辺),
        地表の層のタイル,
    })
}
