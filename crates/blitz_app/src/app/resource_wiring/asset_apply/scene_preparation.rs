//! 起動時シーンの反映準備: 読み直した起動時シーンを、レンダラーへ渡す描画シーン素材・台帳へ入れる登録一式・預かって
//! ある遠景の描画入力へ、状態を1つも変えずに変換し終えた形。変換も動く個体の宣言も読むだけであり、書き換えるものは無い。
//! 内容が同じ回は変換せず、内容だけを運んでホットリローダーの世代へ載せる。

use blitz_engine::実行時シーンの内容;
use blitz_render::描画シーン素材;

use super::error::実行時アセット一式の反映エラー;
use crate::app::draw_bundle_ledger::描画束の台帳;
use crate::app::scene_load::{シーンをレンダラー入力に変換する, シーンを描画入力へ写す材料, 束の描画入力, 束の登録一式, 起動時シーンの所有チャンク, 起動時シーンの束ID};
use crate::hot_reload::起動時シーンの更新;
use crate::world_execution::ゲーム配線;

pub(super) enum 起動時シーンの反映準備 {
    同じ内容 {
        内容: 実行時シーンの内容,
    },
    変更あり {
        内容: 実行時シーンの内容,
        差し替え: Box<起動時シーンの差し替え材料>,
    }, // 描画シーン素材と登録一式と遠景で大きくなるためBoxで持つ(clippy::large_enum_variant)
}

/// レンダラーへ渡す描画シーンと、その直後に台帳へ据える2つ。3つは同じシーンから同時に作られ、別々に据えると束と台帳が食い違う。
pub(super) struct 起動時シーンの差し替え材料 {
    pub(super) 描画シーン: 描画シーン素材,
    pub(super) 登録一式: 束の登録一式,
    pub(super) 遠景: Option<束の描画入力>, // 遠景を持たない世界では無い
}

impl 起動時シーンの反映準備 {
    pub(super) fn 組む(
        更新: 起動時シーンの更新, 並べ方: crate::cli::描画対象の並べ方, 写す材料: シーンを描画入力へ写す材料<'_>, ゲーム配線: &ゲーム配線, 台帳: &描画束の台帳
    ) -> Result<Self, 実行時アセット一式の反映エラー> {
        match 更新 {
            起動時シーンの更新::同じ内容 { 内容 } => Ok(Self::同じ内容 { 内容 }),
            起動時シーンの更新::変更あり { 内容, シーン } => {
                let mut 描画入力 = シーンをレンダラー入力に変換する(&シーン, 並べ方, 起動時シーンの所有チャンク, 写す材料).map_err(実行時アセット一式の反映エラー::起動時シーン変換失敗)?;
                ゲーム配線
                    .束の描画シーン素材へ動く個体を宣言する(起動時シーンの束ID, &mut 描画入力.描画シーン)
                    .map_err(実行時アセット一式の反映エラー::動く個体の宣言失敗)?;
                let 遠景 = 台帳.預かってある遠景を写し直す(写す材料).map_err(実行時アセット一式の反映エラー::遠景変換失敗)?;
                Ok(Self::変更あり {
                    内容,
                    差し替え: Box::new(起動時シーンの差し替え材料 {
                        描画シーン: 描画入力.描画シーン,
                        登録一式: 描画入力.登録一式,
                        遠景,
                    }),
                })
            }
        }
    }
}
