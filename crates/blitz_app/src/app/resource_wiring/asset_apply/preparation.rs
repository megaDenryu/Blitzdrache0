//! 反映準備: 公開済み一式のうち、状態を1つも変えずに確定できるものを全部揃えた材料。一辺の検査・高さ場・地表の層の
//! タイル(`validation`)、起動時シーンと遠景の変換(`scene_preparation`)、旧世界の束ID一覧をここが持つ。
//! 写す材料はここで作った新しいタイルから組むため、タイルを台帳へ据える前にシーンを変換できる。
//! 受け取るのはストリーミングの有無と反映先の読み取りと公開済み一式だけであり、どれも書き換えない。

use blitz_render::描画束ID;

use super::error::実行時アセット一式の反映エラー;
use super::scene_preparation::起動時シーンの反映準備;
use super::validation::反映前の検査を通す;
use crate::app::resource_wiring::hot_reload_check::ホットリロードの反映先;
use crate::app::scene_load::地表の層のタイル一式;
use crate::app::streaming::ストリーミングの有無;
use crate::hot_reload::公開済みの実行時アセット一式;

pub(super) struct 反映準備 {
    pub(super) 高さ場: crate::world_execution::ゲーム用高さ場,
    pub(super) 地表の層のタイル: 地表の層のタイル一式,
    pub(super) 起動時シーン: 起動時シーンの反映準備,
    pub(super) チャンク目録: blitz_engine::チャンク目録,
    pub(super) 旧世界の束一覧: Vec<描画束ID>, // ストリーミングを使わない起動では空
    pub(super) カタログ: blitz_engine::カタログ,
    pub(super) 公開完了印: crate::runtime_assets::生成台帳の公開内容,
}

impl 反映準備 {
    /// どれか1つでも作れなければ、この世代の一式を採用しない。返す前に書き換えた状態は1つも無い。
    pub(super) fn 状態を変えずに組む(
        ストリーミング: &ストリーミングの有無, 反映先: &ホットリロードの反映先<'_>, 一式: 公開済みの実行時アセット一式
    ) -> Result<Self, 実行時アセット一式の反映エラー> {
        let 検査済み = 反映前の検査を通す(ストリーミング, &*反映先.ゲーム配線, &一式)?;
        let 写す材料 = 検査済み.地表の層のタイル.写す材料を組む(反映先.大域ずらし量, 検査済み.一辺);
        let 起動時シーン = 起動時シーンの反映準備::組む(一式.起動時シーン, 反映先.描画対象の並べ方, 写す材料, &*反映先.ゲーム配線, &*反映先.描画束の台帳)?;
        let 旧世界の束一覧 = match ストリーミング.配線を借りる() {
            None => Vec::new(),
            Some(配線) => 配線.旧世界の束一覧を集める().map_err(実行時アセット一式の反映エラー::旧世界の束ID生成失敗)?,
        };
        Ok(Self {
            高さ場: 検査済み.高さ場,
            地表の層のタイル: 検査済み.地表の層のタイル,
            起動時シーン,
            チャンク目録: 一式.チャンク目録,
            旧世界の束一覧,
            カタログ: 一式.カタログ,
            公開完了印: 一式.公開完了印,
        })
    }
}
