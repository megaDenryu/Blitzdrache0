//! 実行時アセット一式の反映が失敗する理由。準備の失敗(状態を1つも変えていない)と、反映の失敗(レンダラーが差し替えを
//! 拒んだ)を枝で区別し、呼び出し側が続けるかどうかと何を出力するかを決められるようにする。

use crate::error::起動エラー;

#[derive(Debug, thiserror::Error)]
pub(in crate::app) enum 実行時アセット一式の反映エラー {
    #[error("チャンク一辺が実行中の世界と違うため一式を採用しなかった: {0}")]
    チャンク一辺不一致(#[from] blitz_engine::チャンク目録差し替えエラー),
    #[error("新しい高さ場を読み込めなかった: {0}")]
    高さ場読込失敗(#[from] blitz_engine::height_field::高さ場読込エラー),
    #[error("新しい地表層テクスチャ集を層のタイルへ写せなかった: {0}")]
    地表の層のタイル変換失敗(起動エラー),
    #[error("読み直した起動時シーンを描画入力へ変換できなかった: {0}")]
    起動時シーン変換失敗(起動エラー),
    #[error("読み直した起動時シーンへ動く個体を宣言できなかった: {0}")]
    動く個体の宣言失敗(blitz_render::レンダラーエラー),
    #[error("預かってある遠景を描画入力へ変換できなかった: {0}")]
    遠景変換失敗(起動エラー),
    #[error("旧世界の描画束IDを作れなかった: {0}")]
    旧世界の束ID生成失敗(起動エラー),
    #[error("レンダラーが起動時シーンの差し替えを拒んだため、何も変えずに旧世界を保った: {0}")]
    レンダラーのシーン差し替え失敗(blitz_render::レンダラーエラー),
    #[error("起動時シーンと遠景を台帳へ再登録できなかった(レンダラーのシーンは新しく、ゲーム世界と世代は旧のまま): {0}")]
    再登録失敗(起動エラー),
}
