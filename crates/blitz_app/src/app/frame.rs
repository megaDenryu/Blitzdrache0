impl アプリ {
    /// RedrawRequestedのたびに1フレーム分の描画を実行する。
    pub(super) fn 一フレーム実行する(&mut self, event_loop: &ActiveEventLoop) {
        if self.レンダラー.is_none() {
            return;
        }
        if let Some(計測) = &mut self.フレーム間隔計測 {
            計測.記録する();
        }
        self.ホットリロードを確認する();
        let アクション = self.この描画の自己操作をウィンドウへ適用する();
        match self.描画機会を通す(アクション) {
            Ok(ゲームの終了要求::続ける) => finish::進めて必要なら終了する(self, event_loop),
            Ok(ゲームの終了要求::終了する) => event_loop.exit(),
            Err(誤り) => {
                self.起動時エラー = Some(誤り);
                event_loop.exit();
            }
        }
    }

    /// 描画機会の中の実行順序: 入力確定→必要な本数だけ固定刻みを進める→描画用状態を組み立てる→描画。
    /// 描画用状態の組み立ての先頭で供給値を混ぜるのは、混ぜた値が描画機会ごとの時間意味に属し、
    /// 固定刻みで確定するゲーム状態を1つも書き換えないためである(参照: `_doc/設計/時間の規律.md`「判断6」)。
    /// ゲーム更新を入力の確定直後・カメラの更新より前に置くのは、プレイヤーの位置がカメラとストリーミングの
    /// 導出元になるためである(判断1)。前へ進む向きはこのフレームのカメラ操作を反映する前のヨーであり、
    /// カメラの更新をゲーム更新より後に置く順序から決まる。
    /// UIの組み立てを描画入力の作成より先に行うのは、露出スライダーの変更を同じフレームの描画へ反映するためである。
    fn 描画機会を通す(&mut self, アクション: スモークアクション) -> Result<ゲームの終了要求, 起動エラー> {
        let インテント = self.入力状態.インテントを確定する();
        // 刻み数と補間の割合はカメラ操作の確定と同じく1描画に1度だけ決める。無期限実行はここで実時間を読む。
        let 時間の進み = self.時間進行.この描画の時間の進みを決める();
        if self.この描画の刻み数だけゲームを進める(時間の進み.刻み数()) == ゲームの終了要求::終了する {
            return Ok(ゲームの終了要求::終了する);
        }
        // 描画へ渡す供給値を混ぜるのはカメラの更新より前である。カメラの注視点が、描く個体と同じ混ぜた位置を追うためである。
        self.ゲーム配線.描画へ渡す供給値をこの描画の割合で混ぜ直す(時間の進み.補間の割合());
        self.カメラをこの描画の視点へ更新する(インテント, &時間の進み)?;
        self.ストリーミングを進める()?;
        self.時刻と天空をこの描画の刻み数へ追随させる(時間の進み.刻み数());
        let 布入力 = self.布フレーム入力を作る(時間の進み.刻み数())?;
        let ui描画 = self.ui描画データを組み立てる()?;
        // 視点は可視判定と描画入力の両方が使うため、1フレームに1度だけ作って配る。
        let 視点情報 = draw_input::視点を求める(self);
        self.この描画の可視個体を選別する(&視点情報)?;
        borrowed_draw::受け皿を預けて描画する(self, アクション, &視点情報, 布入力, ui描画)?;
        Ok(ゲームの終了要求::続ける)
    }

    /// そのフレームの自己操作を決め、スモーク実行を持つ起動ならウィンドウへ適用する。
    fn この描画の自己操作をウィンドウへ適用する(&mut self) -> スモークアクション {
        let アクション = action::選ぶ(self);
        if let (Some(スモーク実行), Some(window)) = (&self.スモーク実行, &self.window) {
            スモーク実行.ウィンドウへ自己操作を適用する(window, アクション);
        }
        アクション
    }
}
