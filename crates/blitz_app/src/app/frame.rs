//! 1フレーム実行: ホットリロード確認 → 自己操作判定 →
//! 入力確定→必要な本数だけ固定刻みを進める→描画用状態を組み立てる→描画(描画機会の中の実行順序、コンポジションルートが明示)。
//!
//! 一描画と一刻みを同一視しない。刻みを何本進めるかは時間進行の配線が決め、刻みを回すのは`game_steps`である。
//! 刻みを1本も進めない描画も成立し、その描画も従来どおり絵を出す。
//! 参照: `_doc/設計/時間の規律.md`「判断9」。

mod action;
mod borrowed_draw;
mod camera_follow;
mod draw_input;
#[cfg(test)]
mod draw_input_tests;
mod finish;
mod game_steps;

use winit::event_loop::ActiveEventLoop;

use super::アプリ;

pub(super) use draw_input::frame_view::カメラ大域位置を組み立てる;
pub(crate) use draw_input::フレーム視点;
pub(super) use draw_input::{描画の計測つまみ, 組み立てる as 描画入力を組み立てる, 視点の履歴};

impl アプリ {
    /// RedrawRequestedのたびに1フレーム分の描画を実行する。
    pub(super) fn 一フレーム実行する(&mut self, event_loop: &ActiveEventLoop) {
        if self.レンダラー.is_none() {
            return;
        }
        if let Some(計測) = &mut self.フレーム間隔計測 {
            計測.記録する();
        }
        self.ホットリロードを確認する();

        let アクション = action::選ぶ(self);
        if let (Some(スモーク実行), Some(window)) = (&self.スモーク実行, &self.window) {
            スモーク実行.ウィンドウへ自己操作を適用する(window, アクション);
        }

        // 描画機会の中の実行順序: 入力確定→必要な本数だけ固定刻みを進める→描画用状態を組み立てる→描画。
        // UI組み立てを描画入力の作成より先に行うのは、露出スライダーの変更を同じフレームの描画へ反映するため。
        let インテント = self.入力状態.インテントを確定する();
        // 刻み数はカメラ操作の確定と同じく1描画に1度だけ決める。無期限実行はここで実時間を読む。
        let 刻み数 = self.時間進行.この描画で進める刻み数を決める();
        // ゲーム更新は入力を確定した直後・カメラの更新より前に置く。プレイヤーの位置がカメラとストリーミングの導出元になるためである(判断1)。
        // 前へ進む向きはこのフレームのカメラ操作を反映する前のヨーである。カメラの更新をゲーム更新より後に置く順序から決まる。
        if self.この描画の刻み数だけゲームを進める(刻み数) == crate::game::ゲームの終了要求::終了する {
            event_loop.exit();
            return;
        }
        camera_follow::ゲームが供給する位置へ注視点を移す(self);
        self.カメラ.更新する(インテント);
        if let Some(探査) = &mut self.個体詳細段探査 {
            探査.適用する(&mut self.カメラ, self.現在フレーム);
        }
        // 必要チャンク集合の中心は確定した視点位置から決めるため、カメラ更新の直後に置く。
        if let Err(誤り) = self.ストリーミングを進める() {
            self.起動時エラー = Some(誤り);
            event_loop.exit();
            return;
        }
        // アニメーション時刻と天空は、その描画で進めた刻み数×基本刻みへ追随させる。実時間を直に読まないため、
        // 同じ本数を進めた実行は必ず同じ時刻で終わり、フレーム数の決まった実行は毎描画1本で従来と同じ歩進になる。
        let この描画で進んだゲームの時間 = self.時間進行.刻み数ぶんの秒を求める(刻み数);
        self.アニメ時刻 = self.アニメ時刻 + この描画で進んだゲームの時間;
        // 時刻はこのフレームの可視判定より先に確定させる。ライト視錐台の導出が方向光の向きを読むためである。
        self.天空.進める(この描画で進んだゲームの時間);
        // 段差の走査は時計を進めた後に条件を据える。据えた時刻を同じフレームの進行が上書きしないためである。
        self.天空.撮影の条件を据える(self.現在フレーム);
        // 自動露出の経過秒は時計の進行と別に確定させる。時計を止めた実行でも露出の追従は進むためである。
        self.天空.自動露出の経過秒を進める();
        let 布入力 = match self.布フレーム入力を作る(刻み数) {
            Ok(入力) => 入力,
            Err(誤り) => {
                self.起動時エラー = Some(誤り);
                event_loop.exit();
                return;
            }
        };
        let ui描画 = match self.ui描画データを組み立てる() {
            Ok(データ) => データ,
            Err(誤り) => {
                self.起動時エラー = Some(誤り);
                event_loop.exit();
                return;
            }
        };
        // 視点は可視判定と描画入力の両方が使うため、1フレームに1度だけ作って配る。
        let 視点情報 = draw_input::視点を求める(self);
        // 計測が無効な実行では時刻を1度も読まない。読むと既存の性能時系列の条件が指定なしで変わる。
        let 可視個体の選別の開始 = self.可視個体の選別の計測.as_ref().map(|_| std::time::Instant::now());
        let 可視個体の選別の結果 = self
            .可視判定
            // 可視判定はずらし無しを読む。1画素未満の揺れで視錐台の境界の対象が出入りすると、描画対象の集合がフレームごとに変わる。
            .判定する(視点情報.ビュー射影の組.ずらし無し(), self.天空.ライティング(), 視点情報.カメラ大域位置);
        if let (Some(開始), Some(計測)) = (可視個体の選別の開始, &mut self.可視個体の選別の計測) {
            計測.記録する(開始.elapsed());
        }
        if let Err(誤り) = 可視個体の選別の結果 {
            self.起動時エラー = Some(誤り);
            event_loop.exit();
            return;
        }
        let 実行結果 = borrowed_draw::受け皿を預けて描画する(self, アクション, &視点情報, 布入力, ui描画);
        if let Err(誤り) = 実行結果 {
            self.起動時エラー = Some(誤り);
            event_loop.exit();
            return;
        }

        finish::進めて必要なら終了する(self, event_loop);
    }
}
