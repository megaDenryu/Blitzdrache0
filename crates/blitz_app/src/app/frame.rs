impl アプリ {
    /// RedrawRequestedのたびに1フレーム分の描画を実行する。
    pub(super) fn 一フレーム実行する(&mut self, event_loop: &ActiveEventLoop) {
        // 据え付けが揃う前の描画機会はここで弾く。この1箇所の判定が、下流の工程が据え付けを無条件に借りてよい根拠である。
        if self.据え付け.is_none() {
            return;
        }
        self.検収の観測.フレーム間隔を記録する();
        self.ホットリロードを確認する();
        // 描画機会の番号は時間進行が保持し、描画機会の途中で変わらない。ここでは自己操作の判定へ配るために読み、
        // 描画機会を通す工程は`この描画の時間の進み`に載った同じ番号を読む。
        let 描画機会の番号 = self.時間進行.現在の描画機会の番号();
        match self.描画機会を通す(描画機会の番号) {
            Ok(ゲームの終了要求::続ける) => {
                if self.時間進行.次の描画機会へ進める(self.起動モード) == 描画機会の続き::描画機会の総数に達した {
                    event_loop.exit();
                }
            }
            Ok(ゲームの終了要求::終了する) => event_loop.exit(),
            Err(誤り) => {
                self.起動時エラー = Some(誤り);
                event_loop.exit();
            }
        }
    }

    /// 描画機会の中の実行順序: 自己操作判定→入力確定→必要な本数だけ固定刻みを進める→描画用状態を組み立てる→描画。
    /// 描画用状態の組み立ての先頭で供給値を混ぜるのは、混ぜた値が描画機会ごとの時間意味に属し、
    /// 固定刻みで確定するゲーム状態を1つも書き換えないためである(参照: `_doc/設計/時間の規律.md`「判断6」)。
    /// ゲーム更新を入力の確定直後・カメラの更新より前に置くのは、プレイヤーの位置がカメラとストリーミングの
    /// 導出元になるためである(判断1)。前へ進む向きはこのフレームのカメラ操作を反映する前のヨーであり、
    /// カメラの更新をゲーム更新より後に置く順序から決まる。
    /// UIの組み立てを描画入力の作成より先に行うのは、露出スライダーの変更を同じフレームの描画へ反映するためである。
    fn 描画機会を通す(&mut self, 描画機会の番号: 描画機会の番号) -> Result<ゲームの終了要求, 起動エラー> {
        let アクション = self.この描画の自己操作をウィンドウへ適用する(描画機会の番号);
        let 意図 = self.入力状態.意図を確定する();
        // 刻み数と補間の割合はカメラ操作の確定と同じく1描画に1度だけ決める。無期限実行はここで実時間を読む。
        let 時間の進み = self.時間進行.この描画の時間の進みを決める();
        if self.この描画の刻み数だけゲームを進める(時間の進み.刻み数())? == ゲームの終了要求::終了する {
            return Ok(ゲームの終了要求::終了する);
        }
        // 描画へ渡す供給値を混ぜるのはカメラの更新より前である。カメラの注視点が、描く個体と同じ混ぜた位置を追うためである。
        self.ゲーム配線.描画へ渡す供給値をこの描画の割合で混ぜ直す(時間の進み.補間の割合());
        self.カメラをこの描画の視点へ更新する(意図, &時間の進み)?;
        self.ストリーミングを進める(時間の進み.描画機会の番号())?;
        self.時刻と天空をこの描画の刻み数へ追随させる(&時間の進み);
        let 布入力 = self.この描画の布入力を作る(時間の進み.刻み数())?;
        let ui描画 = self.ui描画データを組み立てる()?;
        // 視点は可視判定と描画入力の両方が使うため、1フレームに1度だけ作って配る。描画機会の番号もここから下流へ載せて配る。
        let 物理寸法 = 画面の据え付け::描画の最中に見る(&self.据え付け).ウィンドウの物理寸法();
        let 視点情報 = self.視点.この描画の視点を求める(物理寸法, self.大域ずらし量, self.世界の描画構成.時間再構成の描画設定.方式, 時間の進み.描画機会の番号());
        self.この描画の可視個体を選別する(&視点情報)?;
        self.受け皿を預けて描画する(アクション, &視点情報, 布入力, ui描画)?;
        Ok(ゲームの終了要求::続ける)
    }

    /// そのフレームの自己操作を決め、ウィンドウを動かすものをここで適用する。カメラを動かすものはカメラの更新の工程が適用する。
    fn この描画の自己操作をウィンドウへ適用する(&mut self, 描画機会の番号: 描画機会の番号) -> スモークアクション {
        let アクション = self.自己操作.この描画の自己操作を決める(描画機会の番号);
        self.自己操作.ウィンドウへ適用する(画面の据え付け::描画の最中に見る(&self.据え付け).ウィンドウを見る(), アクション);
        アクション
    }
}
