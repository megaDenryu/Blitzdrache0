//! シーンごとの初期ライト方針の引き当て。担当するのは、世界の種別からどの世界の方針を選ぶかと、
//! 局所光の件数の上書きを読まない世界へその指定が来たときに失敗させることだけである。
//! 方針そのものは世界ごとのモジュールが持ち、多段影の設定は`cascade_policy`が全世界ぶんを持つ。
//! 既定は`blitz_engine`の既定ライティングであり、方針を持たない世界はすべてそれになる。

#[cfg(test)]
mod light_count_tests;

mod cascade_policy;
mod indirect_probe;
mod night_lights;
mod stone_hut_interior;
mod vegetation_verification;

use blitz_math::大域ワールド位置;
use blitz_render::ライティング入力;

use crate::cli::{
    世界の種別, 地形の夜灯り世界の綴り, 地形世界の種別, 小物世界の種別, 局所光の件数の起動指定, 影を落とす灯の件数の起動指定,
    石の小屋の屋内の小物世界の綴り, 起動時シーン,
};
use crate::error::起動エラー;

pub(super) fn シーン初期ライティングを作る(
    シーン: &起動時シーン,
    有効: bool,
    大域ずらし量: 大域ワールド位置,
    シャドウ計測: &crate::cli::シャドウ計測起動設定,
    局所光の件数: 局所光の件数の起動指定,
    影を落とす灯の件数: 影を落とす灯の件数の起動指定,
) -> Result<ライティング入力, 起動エラー> {
    let 種別 = シーン.種別();
    let 多段設定 = cascade_policy::シーンの多段設定を作る(種別, シャドウ計測);
    if 種別 == 世界の種別::地形世界(地形世界の種別::夜灯り) {
        return Ok(night_lights::方針を作る(有効, 大域ずらし量, 局所光の件数, 影を落とす灯の件数).多段設定を差し替える(多段設定));
    }
    if 種別 == 世界の種別::小物世界(小物世界の種別::石の小屋の屋内) {
        return Ok(stone_hut_interior::方針を作る(有効, 大域ずらし量, 局所光の件数, 影を落とす灯の件数)?.多段設定を差し替える(多段設定));
    }
    局所光の件数の上書きを読まない世界であることを確かめる(シーン, 局所光の件数)?;
    if 種別 == 世界の種別::間接照明の検収世界 {
        return Ok(indirect_probe::方針を作る(有効, 大域ずらし量).多段設定を差し替える(多段設定));
    }
    if let 世界の種別::植生の検収世界(植生の種別) = 種別 {
        return Ok(vegetation_verification::方針を作る(植生の種別, 有効, 大域ずらし量).多段設定を差し替える(多段設定));
    }
    Ok(blitz_engine::既定ライティングを作る(有効, 大域ずらし量).多段設定を差し替える(多段設定))
}

/// 局所光の件数の上書きを読む世界は夜と屋内の2つの検収世界だけである。読まない世界へ指定が来たら、
/// 起動の時点で失敗させる。黙って捨てると、件数を振ったつもりの計測が全部同じ条件の繰り返しになる。
fn 局所光の件数の上書きを読まない世界であることを確かめる(
    シーン: &起動時シーン,
    局所光の件数: 局所光の件数の起動指定,
) -> Result<(), 起動エラー> {
    match 局所光の件数 {
        局所光の件数の起動指定::世界の宣言に従う => Ok(()),
        局所光の件数の起動指定::件数を上書きする(_) => {
            Err(起動エラー::局所光の件数の上書きを読まない世界(format!(
                "{}(読むのは{地形の夜灯り世界の綴り}と{石の小屋の屋内の小物世界の綴り}だけである)",
                シーン.安定id()
            )))
        }
    }
}
