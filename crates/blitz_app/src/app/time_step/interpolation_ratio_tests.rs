//! 描画補間の割合の検証。実時間を1度も読まないため、どの計算機で何度走らせても同じ結果になる。

use blitz_math::秒;

use super::interpolation_ratio::描画補間の割合;

fn 基本刻み() -> 秒 {
    秒::生成する(1.0 / 60.0)
}

/// 反証: ここが0でない係数を答えると、フレーム数の決まった実行の絵が刻み境界の確定値から動き、
/// 補間の導入だけで既存のスモークと検収の読み戻しが変わる。
#[test]
fn 現在の確定値そのものの割合は前の確定値の側へ1つも戻さない() {
    assert_eq!(描画補間の割合::現在の確定値そのもの().前の確定値の側へ戻す係数(), 0.0);
}

/// 反証: 余りが0の描画で係数が1にならないと、刻みを確定した直後の描画が前の確定値を飛ばして描く。
#[test]
fn 余りが0の割合は前の確定値そのものになる() {
    let 割合 = 描画補間の割合::蓄積の余りと基本刻みから求める(秒::生成する(0.0), 基本刻み());
    assert_eq!(割合.前の確定値の側へ戻す係数(), 1.0);
}

#[test]
fn 余りが基本刻みの半分なら係数も半分になる() {
    let 割合 = 描画補間の割合::蓄積の余りと基本刻みから求める(基本刻み() * 0.5, 基本刻み());
    assert!((割合.前の確定値の側へ戻す係数() - 0.5).abs() < 1.0e-6);
}

/// 反証: 頭打ちにしないと、上限で刻みを打ち切った描画の係数が1を越え、現在の確定値の先へ位置を外挿する。
#[test]
fn 余りが基本刻みを越えても係数は負にならない() {
    let 割合 = 描画補間の割合::蓄積の余りと基本刻みから求める(基本刻み() * 3.0, 基本刻み());
    assert_eq!(割合.前の確定値の側へ戻す係数(), 0.0);
}
