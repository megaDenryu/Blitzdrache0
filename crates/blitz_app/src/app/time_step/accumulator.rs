//! 実時間の蓄積器。担当するのは「描画機会ごとに実時間の経過を貯め、基本刻み1つぶん貯まるごとに固定刻みを1本数える」ことだけであり、
//! 刻みの中で何が起きるかも、上限が何本かも知らない(上限は方針が答える)。
//!
//! 実時間を読むのは`実時間の経過を読んで刻み数を決める`の1メソッドだけである。貯める量を引数で受け取る
//! `経過を貯めて刻み数を決める`を分けてあるのは、貯まり・上限での打ち切り・超過分の破棄・境界ちょうどの4つを
//! 実時間に依らない単体テストで確かめるためである。時計を読む側は経過を作って渡すだけになり、決め方を持たない。
//!
//! 貯めた秒を基本刻みで割る形にせず、基本刻みを1本ずつ引く形にしたのは、境界ちょうどの蓄積が浮動小数の丸めで
//! 1本減るのを避けるためである。最初の描画は前回の実時刻を持たないため経過0秒として扱い、刻みを1本も進めない。
//! 参照: `_doc/設計/時間の規律.md`「判断2」「判断4」「判断8」。

use std::time::Instant;

use blitz_math::秒;

use super::policy::時間進行方針;
use super::tick_count::進める刻み数;

pub(super) struct 実時間の蓄積器 {
    前回の実時刻: Option<Instant>,
    貯めた秒: 秒,
}

impl 実時間の蓄積器 {
    pub(super) fn 生成する() -> Self {
        Self {
            前回の実時刻: None,
            貯めた秒: 秒::生成する(0.0),
        }
    }

    /// この型で唯一実時間を読むメソッド。読んだ経過を貯める側へ渡すだけで、刻み数の決め方は持たない。
    pub(super) fn 実時間の経過を読んで刻み数を決める(&mut self, 方針: &時間進行方針) -> 進める刻み数 {
        let 今 = Instant::now();
        let 経過 = self.前回の実時刻.map_or(0.0, |前| 今.duration_since(前).as_secs_f32());
        self.前回の実時刻 = Some(今);
        self.経過を貯めて刻み数を決める(秒::生成する(経過), 方針)
    }

    /// 経過を貯め、貯まったぶんだけ刻みを数えて蓄積から引く。実時間を1度も読まないため単体テストはこちらを叩く。
    pub(super) fn 経過を貯めて刻み数を決める(&mut self, 経過: 秒, 方針: &時間進行方針) -> 進める刻み数 {
        self.貯めた秒 = 方針.蓄積を上限で切り詰める(self.貯めた秒 + 経過);
        let 上限 = 方針.一描画で進める刻み数の上限();
        let 基本刻み = 方針.基本刻み();
        let mut 刻み数 = 進める刻み数::一つも進めない();
        while !刻み数.上限に達したか(上限) && self.貯めた秒 >= 基本刻み {
            self.貯めた秒 = self.貯めた秒 - 基本刻み;
            刻み数 = 刻み数.一つ増やす();
        }
        刻み数
    }
}
