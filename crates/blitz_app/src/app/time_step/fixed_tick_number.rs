//! 起動から数えた固定刻みの番号。担当するのは「今から進める刻みが何番目か」を1つ持ち、番号どうしの前後に答えることだけである。
//! 番号を進めるのは時間進行の配線であり、この型は誰が進めるかを知らない。
//!
//! 描画機会の番号と別の型にするのは、固定刻みが1描画に0本・1本・複数本ありうるため、2つの時計を1つの式に並べる取り違えを
//! 署名で止めるためである。様式は描画機会の番号と同じ(64ビット・飽和なし)であり、上限に達しないことをこの型の不変条件とする。
//! 上限で同じ値に留める飽和加算は、台本の区切りと終了判定を黙って壊すため採らない。
//!
//! 注意: この型は剰余の演算(`Rem`)を実装しない。周期の判定(何刻みごとか)を処理の中に`番号 % N`として書けなくするためである。
//! 周期は固定刻みの工程が所有し、最初の低頻度の処理が現れるときに工程だけが呼べる判定の口をここへ足す。
//! 生値へ戻すのは、決定的な台本の定数を組む境界と、終了時の報告が起動から進めた刻みの本数を数える境界だけである。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」。

use std::fmt;

/// 起動から数えた固定刻みの番号。最初の刻みが0である。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
#[repr(transparent)]
pub(crate) struct 固定刻みの番号(u64);

impl 固定刻みの番号 {
    pub(crate) const fn 起動時の最初() -> Self {
        Self(0)
    }

    /// 決定的な台本が段階の区切りを定数で組む境界。起動からの通し番号をそのまま受ける。
    pub(crate) const fn 起動からの通し番号として生成する(通し番号: u64) -> Self {
        Self(通し番号)
    }

    pub(in crate::app) fn 次へ進める(self) -> Self {
        Self(self.0 + 1)
    }

    /// この番号から数えて`本数`だけ後の刻みの番号。台本が「決定の30刻み後」のように区切りを定数で組むために使う。
    pub(crate) const fn 本数だけ後の番号(self, 本数: u64) -> Self {
        Self(self.0 + 本数)
    }

    /// 起動からこの番号の直前までに進めた刻みの本数。最初の刻みが0であるため、番号がそのまま本数になる。
    /// 終了時の報告が「ゲーム更新の回数」として出す境界だけが読む。
    pub(crate) fn 起動から進めた刻みの本数(self) -> u64 {
        self.0
    }
}

impl fmt::Display for 固定刻みの番号 {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

#[cfg(test)]
mod tests {
    use super::固定刻みの番号;

    #[test]
    fn 最初の刻みの番号は0であり次へ進めると1つ増える() {
        let 最初 = 固定刻みの番号::起動時の最初();
        assert_eq!(最初.起動から進めた刻みの本数(), 0);
        assert_eq!(最初.次へ進める(), 固定刻みの番号::起動からの通し番号として生成する(1));
        assert!(最初 < 最初.次へ進める());
    }

    #[test]
    fn 本数だけ後の番号は次へ進めるを本数回繰り返した番号と一致する() {
        let 最初 = 固定刻みの番号::起動時の最初();
        assert_eq!(最初.本数だけ後の番号(3), 最初.次へ進める().次へ進める().次へ進める());
    }
}
