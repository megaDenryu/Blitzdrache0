//! 進め方の選び分けの検証。フレーム数の決まった実行が蓄積器を持たないことを、枝の判別と答えの両方で見る。

use blitz_math::秒;

use super::advance::固定刻みの進め方;
use super::interpolation_ratio::描画補間の割合;
use super::policy::時間進行方針;
use super::tick_count::進める刻み数;
use crate::cli::起動モード;

fn 検証の方針() -> 時間進行方針 {
    時間進行方針::生成する(秒::生成する(1.0 / 60.0), 進める刻み数::生成する(4))
}

/// 反証: 検収の実行が蓄積器を持つと、実時間を読んだぶんだけ刻み数が揺れ、同じ引数の起動が別のフレームで別の状態になる。
#[test]
fn フレーム数の決まった実行は蓄積器を持たず毎描画1刻みだけ進める() {
    let 方針 = 検証の方針();
    for モード in [起動モード::スモーク実行 { フレーム数: 3 }, 起動モード::ベンチ実行 { フレーム数: 3 }] {
        let mut 進め方 = 固定刻みの進め方::起動モードから決める(モード);
        assert!(matches!(進め方, 固定刻みの進め方::一描画につき一刻み進める));
        for _ in 0..8 {
            assert_eq!(進め方.この描画で進める刻み数を決める(&方針), 進める刻み数::一つだけ進める());
        }
    }
}

/// 反証: この枝が現在の確定値そのもの以外の割合を答えると、フレーム数の決まった実行の絵が刻み境界の確定値から動き、
/// 補間の導入だけで既存のスモークと検収の読み戻しが変わる。
#[test]
fn フレーム数の決まった実行の補間の割合は常に現在の確定値そのものである() {
    let 方針 = 検証の方針();
    for モード in [起動モード::スモーク実行 { フレーム数: 3 }, 起動モード::ベンチ実行 { フレーム数: 3 }] {
        let mut 進め方 = 固定刻みの進め方::起動モードから決める(モード);
        for _ in 0..8 {
            進め方.この描画で進める刻み数を決める(&方針);
            assert_eq!(進め方.この描画の補間の割合を求める(&方針), 描画補間の割合::現在の確定値そのもの());
        }
    }
}

#[test]
fn 無期限実行は実時間の蓄積器を持つ() {
    let 進め方 = 固定刻みの進め方::起動モードから決める(起動モード::無期限実行);
    assert!(matches!(進め方, 固定刻みの進め方::実時間を貯めて進める(_)));
}

/// 反証: 最初の描画で刻みを進めると、基準の無い経過をゲームの1刻みとして数えたことになる。
#[test]
fn 無期限実行の最初の描画は刻みを1つも進めない() {
    let 方針 = 検証の方針();
    let mut 進め方 = 固定刻みの進め方::起動モードから決める(起動モード::無期限実行);
    assert_eq!(進め方.この描画で進める刻み数を決める(&方針), 進める刻み数::一つも進めない());
}
