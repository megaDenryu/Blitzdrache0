//! この描画で前の確定値と現在の確定値をどれだけ混ぜるかの割合。担当するのは「割合を1つ持ち、現在の確定値から
//! 前の確定値の側へどれだけ戻すかの係数に答える」ことだけであり、何を混ぜるかも、割合を誰が使うかも知らない。
//!
//! 割合の定義は`_doc/設計/時間の規律.md`「判断6」のとおり、蓄積の余りを基本刻みで割った値である。前の確定値から
//! 現在の確定値へどれだけ進んだ位置を描くかを表し、0で前の確定値、1で現在の確定値になる。
//!
//! 蓄積器を持たない実行が答えるのが0でなく1(`現在の確定値そのもの`)なのは、この定義から決まる。実時間の経路で
//! 余りが増えるほど描く位置は前の確定値から現在の確定値へ進むため、0の側が前の確定値である。ここを0にすると、
//! 余りが増えるほど描く位置が現在の確定値から前の確定値へ戻り、刻みが確定するたびに2刻みぶん前へ跳ぶ鋸歯になる。
//! 検収の経路が求めているのは「補間が現在の確定値そのものになること」であり、その不変は割合の数値ではなく、
//! 蓄積器を持たない枝がこの名前の値だけを答えることで機械的に保たれる。

use blitz_math::秒;

/// 前の確定値から現在の確定値へどれだけ進んだ位置を描くかの割合。0以上1以下である。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub(crate) struct 描画補間の割合(f32);

impl 描画補間の割合 {
    /// 混ぜずに現在の確定値をそのまま描く割合。フレーム数の決まった実行が毎描画で答える値である。
    pub(crate) fn 現在の確定値そのもの() -> Self {
        Self(1.0)
    }

    /// 刻みを数え終えた後に残っている蓄積の余りから求める。上限で刻みを打ち切った描画では余りが基本刻みを
    /// 越えうるため1で頭打ちにする。頭打ちにしないと、現在の確定値の先へ位置を外挿することになる。
    pub(super) fn 蓄積の余りと基本刻みから求める(余り: 秒, 基本刻み: 秒) -> Self {
        assert!(基本刻み > 秒::生成する(0.0), "基本刻みが正でない時間進行方針で描画補間の割合を求めた");
        Self((余り.値() / 基本刻み.値()).clamp(0.0, 1.0))
    }

    /// 試験だけが使う作り口。実行時に割合を作れるのは蓄積の余りからだけであり、混ぜる側が割合を自分で決める口は持たない。
    #[cfg(test)]
    pub(crate) fn 前の確定値から進んだ割合として作る(割合: f32) -> Self {
        Self(割合.clamp(0.0, 1.0))
    }

    /// 現在の確定値から前の確定値の側へ戻す係数。2つの確定値の差へ掛ける無次元の量であり、
    /// 現在の確定値そのものを表す割合では0になる。
    pub(crate) fn 前の確定値の側へ戻す係数(self) -> f32 {
        1.0 - self.0
    }
}
