//! この描画で時間がどれだけ進むかの答え。担当するのは、この描画のフレーム番号と、その描画で進める刻み数と、
//! 前と現在の確定値を混ぜる割合を1組で運ぶことだけである。決め方は持たず、刻みの中で何が起きるかも知らない。
//!
//! 2つを1つの型で返すのは、割合が刻み数を数え終えた後の蓄積の余りから決まるためである。別々の口にすると、
//! 刻み数を決める前に割合を読む呼び出しが署名の上で書けてしまい、前の描画の余りで混ぜた絵が静かに出る。
//! 参照: `_doc/設計/時間の規律.md`「判断6」「判断9」。

use super::frame_number::フレーム番号;
use super::interpolation_ratio::描画補間の割合;
use super::tick_count::進める刻み数;

pub(in crate::app) struct この描画の時間の進み {
    フレーム番号: フレーム番号, // この描画機会の番号。検収の経路の判定と自己操作と画素内ずらしがこれを読む
    刻み数: 進める刻み数,
    補間の割合: 描画補間の割合,
}

impl この描画の時間の進み {
    pub(super) fn 生成する(フレーム番号: フレーム番号, 刻み数: 進める刻み数, 補間の割合: 描画補間の割合) -> Self {
        Self {
            フレーム番号, 刻み数, 補間の割合
        }
    }

    pub(in crate::app) fn フレーム番号(&self) -> フレーム番号 {
        self.フレーム番号
    }

    pub(in crate::app) fn 刻み数(&self) -> 進める刻み数 {
        self.刻み数
    }

    pub(in crate::app) fn 補間の割合(&self) -> 描画補間の割合 {
        self.補間の割合
    }
}
