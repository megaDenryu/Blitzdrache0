//! 起動から数えた描画機会の番号。担当するのは「今何番目の描画か」を1つ持ち、番号どうしの前後と描画機会の総数との
//! 位置関係に答えることだけである。番号を進めるのは時間進行の配線であり、この型は誰が進めるかを知らない。
//!
//! 裸の整数で持たないのは、描画機会の番号・描画機会の総数・進める刻み数がどれも1フレーム実行の同じ場所を流れ、
//! 番号(序数)と本数(基数)を足し合わせても署名が通るためである。番号と本数の比較はこの型のメソッドだけが行い、
//! 呼び出し側が`+ 1 ==`の形で番号と本数を並べる算術を書かない。
//!
//! 注意: 幅が64ビットなのは、番号が上限に達して同じ値に留まる事態を起こさないためである。毎秒1000回描いても
//! 上限に達するまで5億年を要するため、進める算術は上限を検査せず、上限に達しないことをこの型の不変条件とする。
//! 上限で同じ値に留める形(飽和加算)は、奇偶・区切り・終了判定・固定経路を黙って壊すため採らない。
//! 描画機会の総数はコマンド行由来の32ビットのままであり、比較はこの型の中で64ビットへ広げて行う。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断11」。

use std::fmt;

/// 起動から数えた描画機会の番号。最初の描画が0である。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
#[repr(transparent)]
pub(crate) struct 描画機会の番号(u64);

impl 描画機会の番号 {
    pub(crate) fn 起動時の最初() -> Self {
        Self(0)
    }

    pub(in crate::app) fn 次へ進める(self) -> Self {
        Self(self.0 + 1)
    }

    pub(in crate::app) fn 最初の描画機会か(self) -> bool {
        self.0 == 0
    }

    /// 奇数番目の描画か。1フレームおきに往復させる探査が向きを決めるために読む。
    pub(in crate::app) fn 奇数番目か(self) -> bool {
        self.0 % 2 == 1
    }

    /// この番号を描き終えると総フレーム数に達するか。フレーム数の決まった実行の最後の描画がこれである。
    pub(in crate::app) fn 最後の描画機会か(self, 描画機会の総数: u32) -> bool {
        self.0 + 1 == u64::from(描画機会の総数)
    }

    /// 最後のフレームの1つ前か。同一起動内の再現性を見る先行ダンプがこの描画を撮る。
    pub(in crate::app) fn 最後の一つ前の描画機会か(self, 描画機会の総数: u32) -> bool {
        self.0 + 2 == u64::from(描画機会の総数)
    }

    /// 最後の`本数`フレームの中に入るか。本数が総フレーム数を超えるときは全フレームが入る。
    pub(in crate::app) fn 最後の何回かの描画機会に入るか(self, 描画機会の総数: u32, 本数: u32) -> bool {
        self.0 + u64::from(本数.min(描画機会の総数)) >= u64::from(描画機会の総数)
    }

    /// 進めた番号が総フレーム数に達したか。達した描画機会でイベントループを閉じる。
    pub(in crate::app) fn 描画機会の総数に達したか(self, 描画機会の総数: u32) -> bool {
        self.0 >= u64::from(描画機会の総数)
    }

    /// 同じ長さの区切りを繰り返すとき、この番号が何番目の区切りに入るか。段差の走査が撮影の番号を引く。
    pub(in crate::app) fn 区切りの通し番号(self, 区切りの長さ: u32) -> u64 {
        self.0 / 正の区切りの長さ(区切りの長さ)
    }

    /// 同じ長さの区切りを繰り返すとき、この番号がその区切りの最後のフレームか。
    pub(in crate::app) fn 区切りの最後の描画機会か(self, 区切りの長さ: u32) -> bool {
        let 長さ = 正の区切りの長さ(区切りの長さ);
        self.0 % 長さ == 長さ - 1
    }

    /// 境界向けの生値取り出し。`blitz_engine`の画素内ずらしの列・スモークの計画・ストリーミングの固定経路のように、
    /// 番号を算術で使う外の口へ渡すときだけ使う。32ビットを要る口は受け手の側で縮め、収まらない番号を型付きエラーにする。
    pub(in crate::app) fn 境界用の生値(self) -> u64 {
        self.0
    }
}

/// 区切りの長さは1フレーム以上である。0で割る事態をRustの既定のパニックに任せると破られた不変条件が文面に現れないため、ここで名指しする。
fn 正の区切りの長さ(区切りの長さ: u32) -> u64 {
    if 区切りの長さ == 0 {
        panic!("区切りの長さが0である(区切りは1フレーム以上の長さを持つという不変条件が破れている)");
    }
    u64::from(区切りの長さ)
}

impl fmt::Display for 描画機会の番号 {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}
