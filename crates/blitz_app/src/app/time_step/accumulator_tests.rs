//! 実時間の蓄積器の検証。実時間を読まない`経過を貯めて刻み数を決める`だけを叩くため、
//! どの計算機で何度走らせても同じ結果になる。

use blitz_math::秒;

use super::accumulator::実時間の蓄積器;
use super::policy::時間進行方針;
use super::tick_count::進める刻み数;

/// 検証で使う方針。基本刻みは1/60秒、上限は4本である。
fn 検証の方針() -> 時間進行方針 {
    時間進行方針::生成する(秒::生成する(1.0 / 60.0), 進める刻み数::生成する(4))
}

#[test]
fn 基本刻みに届かない経過では刻みを1つも進めない() {
    let 方針 = 検証の方針();
    let mut 蓄積器 = 実時間の蓄積器::生成する();
    let 刻み数 = 蓄積器.経過を貯めて刻み数を決める(方針.基本刻み() * 0.5, &方針);
    assert_eq!(刻み数, 進める刻み数::一つも進めない());
}

/// 反証: 端数を捨てて毎回0へ戻すと、基本刻みより短い描画が続く限りゲームが永遠に進まない。
#[test]
fn 届かなかった端数は次の描画へ持ち越される() {
    let 方針 = 検証の方針();
    let mut 蓄積器 = 実時間の蓄積器::生成する();
    assert_eq!(
        蓄積器.経過を貯めて刻み数を決める(方針.基本刻み() * 0.5, &方針),
        進める刻み数::一つも進めない()
    );
    assert_eq!(
        蓄積器.経過を貯めて刻み数を決める(方針.基本刻み() * 0.5, &方針),
        進める刻み数::一つだけ進める()
    );
}

/// 反証: 基本刻みちょうどで1本進まないと、垂直同期のとおりに届く描画がすべて端数の持ち越しになる。
#[test]
fn 基本刻みちょうどの経過は1本だけ進める() {
    let 方針 = 検証の方針();
    let mut 蓄積器 = 実時間の蓄積器::生成する();
    for _ in 0..5 {
        assert_eq!(蓄積器.経過を貯めて刻み数を決める(方針.基本刻み(), &方針), 進める刻み数::一つだけ進める());
    }
}

#[test]
fn 貯まったぶんだけまとめて刻みを進める() {
    let 方針 = 検証の方針();
    let mut 蓄積器 = 実時間の蓄積器::生成する();
    let 刻み数 = 蓄積器.経過を貯めて刻み数を決める(方針.基本刻み() * 3.5, &方針);
    assert_eq!(刻み数, 進める刻み数::生成する(3));
}

/// 反証: 上限で打ち切らないと、長い停止から復帰した1描画が何百本もの刻みを回して更に落ちる。
#[test]
fn 上限を越える経過でも上限の本数までしか進めない() {
    let 方針 = 検証の方針();
    let mut 蓄積器 = 実時間の蓄積器::生成する();
    let 刻み数 = 蓄積器.経過を貯めて刻み数を決める(方針.基本刻み() * 100.0, &方針);
    assert_eq!(刻み数, 方針.一描画で進める刻み数の上限());
}

/// 反証: 上限を越えた蓄積を残すと、恒常的な過負荷で蓄積が際限なく育ち、以後の描画が永遠に上限いっぱいを回し続ける。
#[test]
fn 上限を越えて貯まった分は捨てられ次の描画へ残らない() {
    let 方針 = 検証の方針();
    let mut 蓄積器 = 実時間の蓄積器::生成する();
    蓄積器.経過を貯めて刻み数を決める(方針.基本刻み() * 100.0, &方針);
    assert_eq!(
        蓄積器.経過を貯めて刻み数を決める(秒::生成する(0.0), &方針),
        進める刻み数::一つも進めない()
    );
}
