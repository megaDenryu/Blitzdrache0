//! 時間進行配線が固定刻みの番号を起動時の最初から持ち、進めるたびに1つ増やすことの検証。
//! ゲームを遊ぶかどうかの情報をこの口が受け取らないため、遊ばない起動でも進めれば同じだけ増える。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断13」。

use blitz_math::秒;

use super::policy::時間進行方針;
use super::tick_count::進める刻み数;
use super::{固定刻みの番号, 時間進行配線};
use crate::cli::起動モード;

fn 検証の方針() -> 時間進行方針 {
    時間進行方針::生成する(秒::生成する(1.0 / 60.0), 進める刻み数::生成する(4))
}

#[test]
fn 固定刻みの番号は起動時の最初から始まり進めた本数だけ増える() {
    let mut 時間進行 = 時間進行配線::起動モードから作る(起動モード::無期限実行, 検証の方針());
    assert_eq!(時間進行.現在の固定刻みの番号(), 固定刻みの番号::起動時の最初());
    for _ in 0..3 {
        時間進行.次の固定刻みへ進める();
    }
    assert_eq!(時間進行.現在の固定刻みの番号(), 固定刻みの番号::起動時の最初().本数だけ後の番号(3));
}
