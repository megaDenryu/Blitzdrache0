//! 固定刻みをどう進めるかの方針。担当するのは「実行の種類から進め方を1つ決める」ことと「その描画で進める刻み数を1つ答える」
//! ことだけである。刻みの中身も方針の値も知らない。
//!
//! 実行の種類で1度だけ選ぶのは、カメラ操作の適用方針(`input/camera_intent_policy.rs`)と
//! 自動露出の経過秒源(`app/time_of_day/exposure_elapsed.rs`)と同じ形の判断だからである。時間源をトレイトで差し替えない。
//! フレーム数の決まった実行が蓄積器を持たないのは、実時間を1度でも読むと読み戻した絵と検収の合否が実行ごとに揺れるためである。
//! この枝は実時間を読む口を1つも持たず、必ず1描画につき1刻みを答える。
//! 参照: `_doc/設計/時間の規律.md`「判断8」。

use super::accumulator::実時間の蓄積器;
use super::interpolation_ratio::描画補間の割合;
use super::policy::時間進行方針;
use super::tick_count::進める刻み数;
use crate::cli::起動モード;

pub(super) enum 固定刻みの進め方 {
    実時間を貯めて進める(実時間の蓄積器), // 無期限実行。描画機会ごとに実時間を貯め、貯まったぶんだけ刻みを進める
    一描画につき一刻み進める,             // フレーム数の決まった実行。実時間を1度も読まず、必ず1刻みだけ進める
}

impl 固定刻みの進め方 {
    /// フレーム数の決まった実行(スモーク・ベンチ・段差走査)は1描画1刻み、無期限実行は実時間を貯めて進める。
    pub(super) fn 起動モードから決める(モード: 起動モード) -> Self {
        match モード {
            起動モード::無期限実行 => Self::実時間を貯めて進める(実時間の蓄積器::生成する()),
            起動モード::スモーク実行 { .. } | 起動モード::ベンチ実行 { .. } | 起動モード::段差走査実行 { .. } => {
                Self::一描画につき一刻み進める
            }
        }
    }

    pub(super) fn この描画で進める刻み数を決める(&mut self, 方針: &時間進行方針) -> 進める刻み数 {
        match self {
            Self::実時間を貯めて進める(蓄積器) => 蓄積器.実時間の経過を読んで刻み数を決める(方針),
            Self::一描画につき一刻み進める => 進める刻み数::一つだけ進める(),
        }
    }

    /// 蓄積を持たない枝が答えるのは常に現在の確定値そのものである。この枝は余りを持ちようがないため、
    /// 描く値が刻み境界の確定状態から動かないことが型の上で決まる。
    pub(super) fn この描画の補間の割合を求める(&self, 方針: &時間進行方針) -> 描画補間の割合 {
        match self {
            Self::実時間を貯めて進める(蓄積器) => 蓄積器.この描画の補間の割合を求める(方針),
            Self::一描画につき一刻み進める => 描画補間の割合::現在の確定値そのもの(),
        }
    }
}
