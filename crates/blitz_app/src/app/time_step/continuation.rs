//! フレームを1つ進めた後に実行を続けるかどうかの答え。担当するのは、時間進行の配線が総フレーム数と番号を比べた
//! 結果を、呼び出し側がイベントループを閉じるかどうかの判断へそのまま写せる形で運ぶことだけである。
//!
//! 真偽値でなく判別共用体にするのは、`true`が「続ける」なのか「終える」なのかを呼び出し側が取り違えると、
//! フレーム数の決まった実行が1フレームも描かずに終わるか無期限に回り続けるかのどちらかになるためである。

/// フレームを1つ進めた後の実行の続き方。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(in crate::app) enum 描画機会の続き {
    続ける,                 // 次の描画機会を待つ
    描画機会の総数に達した, // フレーム数の決まった実行が最後の描画を終えた。イベントループを閉じる
}
