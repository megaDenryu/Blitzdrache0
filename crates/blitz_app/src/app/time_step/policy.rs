//! 一描画で固定刻みを何本まで進めるかと、1本の長さをまとめた実行方針。担当するのは「基本刻みと上限を答える」ことと
//! 「蓄積を上限で切り詰め、刻み数をその描画で進む時間へ写す」ことだけである。実時間も蓄積の値も持たない。
//!
//! 上限をこの型が持つのは、本数を刻みの繰り返しへ埋め込まないためである。初期値は4だが実測で2・6へ動かす前提であり、
//! 値はコンポジションルートが組んで渡す。基本刻みもゲーム更新の一刻みの秒から受け取り、ここで書き直さない。
//! 切り詰めで捨てた過去の蓄積を後から取り戻さないのは、恒常的な過負荷で蓄積が際限なく育つのを止めるためである。
//! 参照: `_doc/設計/時間の規律.md`「判断3」「判断4」。

use blitz_math::秒;

use super::tick_count::進める刻み数;

/// 基本刻み・一描画で進める刻み数の上限・蓄積の上限・超過分の扱いをまとめた設定。
#[derive(Debug, Clone, Copy)]
pub(in crate::app) struct 時間進行方針 {
    基本刻み: 秒,
    一描画で進める刻み数の上限: 進める刻み数,
}

impl 時間進行方針 {
    pub(in crate::app) fn 生成する(基本刻み: 秒, 一描画で進める刻み数の上限: 進める刻み数) -> Self {
        Self {
            基本刻み,
            一描画で進める刻み数の上限,
        }
    }

    pub(in crate::app) fn 基本刻み(self) -> 秒 {
        self.基本刻み
    }

    pub(in crate::app) fn 一描画で進める刻み数の上限(self) -> 進める刻み数 {
        self.一描画で進める刻み数の上限
    }

    /// 蓄積してよい上限。上限の刻み数をちょうど進めきる長さであり、これを越えた蓄積は捨てる。
    pub(in crate::app) fn 蓄積の上限(self) -> 秒 {
        self.刻み数ぶんの秒を求める(self.一描画で進める刻み数の上限)
    }

    /// その刻み数を進めたときにゲーム世界が進む時間。アニメーション時刻と天空の進行がこの値へ追随する。
    pub(in crate::app) fn 刻み数ぶんの秒を求める(self, 刻み数: 進める刻み数) -> 秒 {
        self.基本刻み * 刻み数.倍率へ写す()
    }

    /// 上限を越えて貯まった実時間を捨てる。遅れを取り戻すために処理量が増え続ける状態を作らないためである。
    pub(in crate::app) fn 蓄積を上限で切り詰める(self, 貯めた秒: 秒) -> 秒 {
        let 上限 = self.蓄積の上限();
        if 貯めた秒 > 上限 { 上限 } else { 貯めた秒 }
    }
}
