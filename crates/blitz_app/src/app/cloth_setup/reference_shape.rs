//! 参照比較の題材の形(敷き方と固定)が決める布の仕様と世界固定点にする粒子(Issue #38「検証シーン」の面)。受け取るのは題材の形、返すのは布仕様と粒子添字の一覧である。
//! 垂直な布は上端の行が高さ1.8メートル、水平な布は全体が高さ1.8メートルの面(行が+Zへ進む)であり、どちらも下端が床に触れない
//! (水平な布が縁から真下へ垂れると下端は0.25メートル)。一点で固定した布は対角線が高さより長く床に触れるが、それは曲げの折り畳みを見る題材として採る。

use blitz_sim::布仕様;

use super::{一辺粒子数, 吊るし間隔, 総質量};
use crate::cli::参照比較の題材の形;

/// 上端行の高さ(垂直)と面の高さ(水平)。垂直では下端行が1.8 − 31×0.05 = 0.25メートルであり床に触れない。
const 上端の高さ: f32 = 1.8;

/// 題材の形ごとの布の仕様。垂直な布は上端の行が高さ1.8メートル、水平な布は全体が高さ1.8メートルの面(行が+Zへ進む)である。
pub(super) fn 題材の形の仕様(形: 参照比較の題材の形) -> Result<布仕様, blitz_sim::布生成エラー> {
    match 形 {
        参照比較の題材の形::垂直に吊るして上端の行を固定 => {
            布仕様::生成する(一辺粒子数, 吊るし間隔, 総質量, [-0.775, 上端の高さ, 0.4])
        }
        参照比較の題材の形::水平に敷いて上端の行を固定
        | 参照比較の題材の形::水平に敷いて上端の行と右端の列を固定
        | 参照比較の題材の形::水平に敷いて上端の左の一点を固定 => {
            布仕様::水平に生成する(一辺粒子数, 吊るし間隔, 総質量, [-0.775, 上端の高さ, -0.375])
        }
    }
}

/// 題材の形ごとの世界固定点にする粒子。上端の行は布データの公開情報、右端の列と上端の左の一点は格子の並び(行×一辺 + 列)から組む。
pub(super) fn 固定する粒子一覧(データ: &blitz_sim::布データ, 形: 参照比較の題材の形) -> Vec<u32> {
    match 形 {
        参照比較の題材の形::垂直に吊るして上端の行を固定 | 参照比較の題材の形::水平に敷いて上端の行を固定 => {
            データ.上端行の粒子添字一覧.clone()
        }
        参照比較の題材の形::水平に敷いて上端の行と右端の列を固定 => {
            let mut 一覧 = データ.上端行の粒子添字一覧.clone();
            一覧.extend((1..一辺粒子数).map(|行| 行 * 一辺粒子数 + 一辺粒子数 - 1));
            一覧
        }
        参照比較の題材の形::水平に敷いて上端の左の一点を固定 => vec![データ.上端行の粒子添字一覧[0]],
    }
}
