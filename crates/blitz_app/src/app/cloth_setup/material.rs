//! 布データと物性からGPU境界の布素材を組む工程。受け取るのは布データ・物性・アタッチ対応・定数、返すのは検証済みの布素材である。
//! 拘束は彩色で色ごとに並べ替えた順でバイト列にし、色の区間とラグランジュ乗数の初期値もここで揃える
//! (レイアウトの契約は`blitz_sim::xpbd_gpu_layout`が持ち、blitz_renderは長さだけを検証する)。

use blitz_render::cloth_material::{布の彩色の区間, 布素材の材料};
use blitz_render::{布定数, 布素材};
use blitz_sim::{xpbd_gpu_layout, 布の彩色済み拘束, 布の物性, 布データ};

use crate::error::起動エラー;

pub(super) fn 布素材を組む(
    データ: &布データ,
    物性: &布の物性,
    アタッチ対応一覧: Vec<[u32; 2]>,
    定数: 布定数,
) -> Result<布素材, 起動エラー> {
    let 拘束 = 布の彩色済み拘束::生成する(データ, 物性)?;
    let 色の区間一覧 = 拘束
        .色の区間一覧()
        .iter()
        .map(|区間| 布の彩色の区間 {
            開始: 区間.開始.値(),
            本数: 区間.本数,
        })
        .collect();
    Ok(布素材::生成する(布素材の材料 {
        粒子バイト列: blitz_sim::粒子バイト列にする(データ),
        拘束の引数バイト列: xpbd_gpu_layout::拘束の引数バイト列にする(拘束.拘束グラフ()),
        ラグランジュ乗数の初期バイト列: xpbd_gpu_layout::ラグランジュ乗数の初期バイト列にする(拘束.拘束の数()),
        色の区間一覧,
        インデックス一覧: データ.描画用インデックス一覧.clone(),
        アタッチ対応一覧,
        一辺粒子数: super::一辺粒子数,
        定数,
    })?)
}
