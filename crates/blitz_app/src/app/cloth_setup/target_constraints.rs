//! 布の目標拘束を組む工程(`_doc/設計/XPBD共通拘束基盤.md`「判断6」)。受け取るのは布データ、返すのは目標拘束のバッチと掴みの枠の添字である。
//! 上端行の各粒子を今の位置へ硬く固定する目標拘束(吊るし布では世界固定点。マントでは目標の確定が毎刻みスキン済み頂点の位置で上書きする初期値)と、
//! 呼び手が足す追加の目標拘束(参照比較の床の下の固定点)と、掴み粒子の無効な枠(掴む介入が目標位置を与えて有効にし、離す介入が無効にする)を
//! 1つのバッチにする。掴みの枠は末尾に置く。粒子の逆質量はどれも物性のまま触らない。

use blitz_sim::constraint_graph::{添字付き目標拘束, 点添字, 目標拘束のバッチ, 目標拘束の目標, 目標拘束添字};
use blitz_sim::{布データ, 目標拘束の引数};

use crate::error::起動エラー;

pub(super) struct 布の目標拘束 {
    pub(super) バッチ: 目標拘束のバッチ,
    pub(super) 掴みの拘束添字: 目標拘束添字,
}

// 上端行を今の位置の世界固定点として硬く固定し、追加の目標拘束を続け、掴み粒子の無効な枠を末尾へ足したバッチ。
pub(super) fn 上端行を固定し掴みの枠を持つ目標拘束を組む(
    データ: &布データ,
    追加の目標拘束一覧: Vec<(添字付き目標拘束, 目標拘束の目標)>,
) -> Result<布の目標拘束, 起動エラー> {
    let mut 一覧: Vec<(添字付き目標拘束, 目標拘束の目標)> = データ
        .上端行の粒子添字一覧
        .iter()
        .map(|&添字| {
            let 位置 = データ.粒子一覧[super::添字をusizeへ変換する(添字)].ワールド位置();
            (
                添字付き目標拘束::生成する(点添字::生成する(添字), 目標拘束の引数::硬い()),
                目標拘束の目標::有効な位置(位置),
            )
        })
        .collect();
    一覧.extend(追加の目標拘束一覧);
    let 掴みの位置 = データ.粒子一覧[super::添字をusizeへ変換する(super::掴み粒子添字)].ワールド位置();
    一覧.push((
        添字付き目標拘束::生成する(点添字::生成する(super::掴み粒子添字), 目標拘束の引数::硬い()),
        目標拘束の目標::無効な位置(掴みの位置),
    ));
    let バッチ = 目標拘束のバッチ::生成する(データ.粒子一覧.len(), 一覧)?;
    let 掴みの拘束添字 = バッチ.添字(バッチ.拘束の数() - 1);
    Ok(布の目標拘束 {
        バッチ, 掴みの拘束添字
    })
}

// アタッチ先の対応(布粒子添字・スキン頂点添字)を、目標の確定が読む対応(目標拘束添字・スキン頂点添字)へ写す。
// 前提: 対応の布粒子はどれも上端行であり、上端行の粒子は全てバッチに目標拘束を持つ(`アタッチ先を選ぶ`と本モジュールの生成が保証する)。
pub(super) fn 目標の更新対応を作る(バッチ: &目標拘束のバッチ, アタッチ対応一覧: &[[u32; 2]]) -> Vec<[u32; 2]> {
    アタッチ対応一覧
        .iter()
        .map(|対応| {
            let 位置 = バッチ.拘束一覧().iter().position(|拘束| 拘束.粒子.値() == 対応[0]).unwrap_or_else(|| {
                panic!(
                    "アタッチ先の布粒子{}に目標拘束が無い(上端行の粒子は全て目標拘束を持つはずの不変条件の破れ)",
                    対応[0]
                )
            });
            [バッチ.添字(位置).値(), 対応[1]]
        })
        .collect()
}
