//! XPBDの参照比較の布(Issue #36「検証」): 吊るし布と同じ32x32の格子を、床(y=0)に触れない高さから吊るす。
//! 自己衝突の分離はGPUの原子加算の順序に依ってCPUで再現できないため、この布は自己衝突を行わず(空間ハッシュと分離の工程を積まない)、
//! 介入も動く目標もカプセルも持たない。GPUが積むのは積分・乗数の零化・色順の距離拘束・目標拘束(上端行の世界固定点と掴みの無効な枠)・床の押し出し・
//! 目標拘束の最終の成立・仕上げであり、CPUの参照計算が仕上げ(速度の再構成)を除く全部を再現する(Issue #37)。
//! 床の下の固定点を持つ題材は、同じ高さから吊るした布の下端の右端を、その粒子の真下の床の下(y=−0.01メートル)の世界固定点にする。
//! 床がその粒子を持ち上げた後の目標拘束の最終の成立が目標へ戻すことを、GPUとCPUで突き合わせるためである。
//! 下端の行が床に触れる高さから吊るす形を採らないのは、床に載った行が毎刻み床に蹴られて速度を作る力学が摂動を増幅し(CPUの参照計算で1e-7メートルの摂動が
//! 12刻みで6e-3メートルへ育つ)、単精度の演算順の差が許容を越えるためである。
//! 参照計算の刻み幅はGPUの定数へ渡すのと同じ注入値から作るため、時間の規律の正本を変えれば両方が同時に動く。

use blitz_math::{メートル, メートル毎秒毎秒, ワールド, 位置};
use blitz_render::cloth_material::布の拘束の反復回数;
use blitz_render::{布の刻み幅, 布の自己衝突, 布定数, 布素材};
use blitz_sim::constraint_graph::{一様な加速度, 添字付き目標拘束, 点添字, 目標拘束の目標};
use blitz_sim::{
    コンプライアンス, 刻み幅, 布の参照計算の条件, 布の彩色済み拘束, 布の物性, 曲げのコンプライアンス, 目標拘束の引数
};

use super::super::cloth_reference::{参照比較の題材, 布の参照比較};
use super::{material, target_constraints, 一辺粒子数, 吊るし間隔, 布プリセット, 掴み写像, 総質量};
use crate::cli::{参照比較の床の下の固定点, 布のコンプライアンス指定};
use crate::error::起動エラー;

/// 上端行の高さ。下端行が1.8 − 31×0.05 = 0.25メートルであり床に触れない。
const 上端の高さ: f32 = 1.8;
/// 床の下の固定点にする粒子(下端行の右端)。掴みの粒子(下端行の左端)とは別である。
const 下端の右端の粒子添字: u32 = 一辺粒子数 * 一辺粒子数 - 1;
/// 床の下の固定点の目標の高さ。床(y=0)の下であり、最終の成立を欠くと床の高さとの差0.01メートルが位置の許容1e-4メートルを越える。
const 床の下の目標の高さ: f32 = -0.01;
const 重力: [f32; 3] = [0.0, -9.8, 0.0];
const 速度減衰: f32 = 0.99;

pub(super) fn 参照比較の布を構築する(
    コンプライアンス指定: 布のコンプライアンス指定,
    床の下の固定点: 参照比較の床の下の固定点,
    布の刻み幅: 布の刻み幅,
) -> Result<(布素材, 布プリセット, 布の参照比較), 起動エラー> {
    let 仕様 = blitz_sim::布仕様::生成する(一辺粒子数, 吊るし間隔, 総質量, [-0.775, 上端の高さ, 0.4])?;
    let データ = blitz_sim::布を生成する(&仕様)?;
    let 追加の目標拘束 = match 床の下の固定点 {
        参照比較の床の下の固定点::持つ => vec![床の下の固定点を組む(&データ)],
        参照比較の床の下の固定点::持たない => Vec::new(),
    };
    let 目標拘束 = target_constraints::上端行を固定し掴みの枠を持つ目標拘束を組む(&データ, 追加の目標拘束)?;
    let 物性 = 布の物性::一様に生成する(コンプライアンス::生成する(コンプライアンス指定.値())?, 曲げのコンプライアンス::硬い());
    let 定数 = 布定数 {
        重力,
        粒子間隔: 吊るし間隔,
        グリッド原点: [-0.8, -0.05, -0.4],
        速度減衰,
        自己衝突: 布の自己衝突::行わない,
        刻み幅: 布の刻み幅,
    };
    let 素材 = material::布素材を組む(&データ, &物性, &目標拘束.バッチ, Vec::new(), 定数)?;
    let 題材 = 参照比較の題材 {
        拘束: 布の彩色済み拘束::生成する(&データ, &物性)?,
        目標拘束: 目標拘束.バッチ,
        条件: 布の参照計算の条件 {
            刻み幅: 刻み幅::生成する(布の刻み幅.秒())?,
            重力: 一様な加速度::成分から生成する(
                メートル毎秒毎秒::生成する(重力[0]),
                メートル毎秒毎秒::生成する(重力[1]),
                メートル毎秒毎秒::生成する(重力[2]),
            ),
            速度減衰,
        },
        反復回数: 布の拘束の反復回数,
        コンプライアンス: コンプライアンス指定.値(),
        一辺粒子数,
    };
    let プリセット = 布プリセット {
        カプセル: None,
        掴み: 掴み写像 {
            中心: [0.0, 0.75, 0.4],
            横基底: [1.2, 0.0, 0.0],
            縦基底: [0.0, 0.75, 0.0],
        },
        掴みの目標拘束添字: 目標拘束.掴みの拘束添字,
    };
    Ok((素材, プリセット, 布の参照比較::始める(題材)))
}

/// 下端の右端の粒子を、その真下の床の下の目標へ硬く固定する世界固定点。
fn 床の下の固定点を組む(データ: &blitz_sim::布データ) -> (添字付き目標拘束, 目標拘束の目標) {
    let 今 = データ.粒子一覧[super::添字をusizeへ変換する(下端の右端の粒子添字)].ワールド位置();
    let 目標 = 位置::<ワールド>::生成する(今.x(), メートル::生成する(床の下の目標の高さ), 今.z());
    (
        添字付き目標拘束::生成する(点添字::生成する(下端の右端の粒子添字), 目標拘束の引数::硬い()),
        目標拘束の目標::有効な位置(目標),
    )
}
