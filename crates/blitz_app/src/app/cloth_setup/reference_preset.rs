//! XPBDの参照比較の布(Issue #36「検証」): 吊るし布と同じ32x32の格子を、床(y=0)に触れない高さから吊るす。
//! 自己衝突の分離はGPUの原子加算の順序に依ってCPUで再現できないため、この布は自己衝突を行わず(空間ハッシュと分離の工程を積まない)、
//! 介入もアタッチもカプセルも持たない。GPUが積むのは積分・乗数の零化・色順の拘束・仕上げであり、CPUの参照計算がその4つを再現する。

use blitz_math::{メートル毎秒毎秒, 秒};
use blitz_render::cloth_material::{布の固定刻みの秒, 布の拘束の反復回数};
use blitz_render::{布の自己衝突, 布定数, 布素材};
use blitz_sim::constraint_graph::一様な加速度;
use blitz_sim::{コンプライアンス, 刻み幅, 布の参照計算の条件, 布の彩色済み拘束, 布の物性};

use super::super::cloth_reference::{参照比較の題材, 布の参照比較};
use super::{material, 一辺粒子数, 吊るし間隔, 布プリセット, 掴み写像, 総質量};
use crate::cli::布のコンプライアンス指定;
use crate::error::起動エラー;

/// 上端行の高さ。下端行が1.8 − 31×0.05 = 0.25メートルであり床に触れない。
const 上端の高さ: f32 = 1.8;
const 重力: [f32; 3] = [0.0, -9.8, 0.0];
const 速度減衰: f32 = 0.99;

pub(super) fn 参照比較の布を構築する(
    コンプライアンス指定: 布のコンプライアンス指定,
) -> Result<(布素材, 布プリセット, 布の参照比較), 起動エラー> {
    let 仕様 = blitz_sim::布仕様::生成する(一辺粒子数, 吊るし間隔, 総質量, [-0.775, 上端の高さ, 0.4])?;
    let mut データ = blitz_sim::布を生成する(&仕様)?;
    for &添字 in &データ.上端行の粒子添字一覧.clone() {
        データ.粒子一覧[super::添字をusizeへ変換する(添字)].逆質量 = 0.0;
    }
    let 物性 = 布の物性::一様に生成する(コンプライアンス::生成する(コンプライアンス指定.値())?);
    let 定数 = 布定数 {
        重力,
        粒子間隔: 吊るし間隔,
        グリッド原点: [-0.8, -0.05, -0.4],
        速度減衰,
        自己衝突: 布の自己衝突::行わない,
    };
    let 素材 = material::布素材を組む(&データ, &物性, Vec::new(), 定数)?;
    let 題材 = 参照比較の題材 {
        拘束: 布の彩色済み拘束::生成する(&データ, &物性)?,
        条件: 布の参照計算の条件 {
            刻み幅: 刻み幅::生成する(秒::生成する(布の固定刻みの秒))?,
            重力: 一様な加速度::成分から生成する(
                メートル毎秒毎秒::生成する(重力[0]),
                メートル毎秒毎秒::生成する(重力[1]),
                メートル毎秒毎秒::生成する(重力[2]),
            ),
            速度減衰,
        },
        反復回数: 布の拘束の反復回数,
        コンプライアンス: コンプライアンス指定.値(),
        一辺粒子数,
    };
    let プリセット = 布プリセット {
        カプセル: None,
        掴み: 掴み写像 {
            中心: [0.0, 0.75, 0.4],
            横基底: [1.2, 0.0, 0.0],
            縦基底: [0.0, 0.75, 0.0],
        },
    };
    Ok((素材, プリセット, 布の参照比較::始める(題材)))
}
