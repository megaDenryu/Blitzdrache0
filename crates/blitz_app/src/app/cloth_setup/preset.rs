//! 吊るし布とマントの初期素材・実行時パラメータを構築する。布の硬さは構造とせん断のコンプライアンスで与え(Issue #36「物性」)、
//! 過緩和係数は持たない。初期値はどちらも硬い拘束(コンプライアンス0)であり、旧経路の硬い距離拘束と同じ物性から始める。

use blitz_render::{布定数, 布素材};

use super::{attach, マント間隔, 一辺粒子数, 吊るし間隔, 布プリセット, 掴み写像, 総質量};
use crate::error::起動エラー;

/// 吊るし布(判断56の既定検証シナリオ): 上端行を空中に固定した布が正対カメラの前(quad構図)に垂れる。
/// スキン・アタッチ・カプセルを使わず、掴む/離す/床接触を最小の変数で見せる。寸法はquadスケール(約1m)。
pub(in crate::app) fn 吊るし布を構築する() -> Result<(布素材, 布プリセット), 起動エラー> {
    let 仕様 = blitz_sim::布仕様::生成する(一辺粒子数, 吊るし間隔, 総質量, [-0.775, 1.5, 0.4])?;
    let mut データ = blitz_sim::布を生成する(&仕様)?;
    for &添字 in &データ.上端行の粒子添字一覧.clone() {
        データ.粒子一覧[super::添字をusizeへ変換する(添字)].逆質量 = 0.0;
    }
    let 定数 = 布定数 {
        重力: [0.0, -9.8, 0.0],
        粒子間隔: 吊るし間隔,
        グリッド原点: [-0.8, -0.05, -0.4],
        速度減衰: 0.99,
    };
    let 素材 = super::material::布素材を組む(&データ, &blitz_sim::布の物性::硬い(), Vec::new(), 定数)?;
    let プリセット = 布プリセット {
        カプセル: None,
        掴み: 掴み写像 {
            中心: [0.0, 0.75, 0.4],
            横基底: [1.2, 0.0, 0.0],
            縦基底: [0.0, 0.75, 0.0],
        },
    };
    Ok((素材, プリセット))
}

/// マント(fox限定): 布は32x32粒子・間隔3.2(幅約99)。重力はcm相当スケールの-980/s^2。
/// キャラ衝突はカプセル1本の近似で脚・首を覆えない(絵作りはドメイン表現層の課題としてM10以降)。
pub(in crate::app) fn マントを構築する(頂点一覧: &[blitz_render::頂点]) -> Result<(布素材, 布プリセット), 起動エラー> {
    let 仕様 = blitz_sim::布仕様::生成する(一辺粒子数, マント間隔, 総質量, [0.0, 0.0, 0.0])?;
    let mut データ = blitz_sim::布を生成する(&仕様)?;
    let アタッチ対応一覧 = attach::アタッチ先を選ぶ(頂点一覧, &データ.上端行の粒子添字一覧);
    attach::初期形状を整形する(&mut データ, 頂点一覧, &アタッチ対応一覧, マント間隔);
    let 定数 = 布定数 {
        重力: [0.0, -980.0, 0.0],
        粒子間隔: マント間隔,
        グリッド原点: [-51.0, 0.0, -51.0],
        速度減衰: 0.985,
    };
    let 素材 = super::material::布素材を組む(&データ, &blitz_sim::布の物性::硬い(), アタッチ対応一覧, 定数)?;
    let プリセット = 布プリセット {
        カプセル: Some(([0.0, 45.0, -45.0], [0.0, 55.0, 45.0], 22.0)),
        掴み: 掴み写像 {
            中心: [0.0, 50.0, 0.0],
            横基底: [0.0, 0.0, -110.0],
            縦基底: [0.0, 70.0, 0.0],
        },
    };
    Ok((素材, プリセット))
}
