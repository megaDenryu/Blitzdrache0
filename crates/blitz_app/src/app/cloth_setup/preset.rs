//! 吊るし布とマントの初期素材・実行時パラメータを構築する。布の硬さは構造とせん断のコンプライアンスと曲げのコンプライアンスで与え(Issue #36「物性」・Issue #38)、
//! 過緩和係数は持たない。距離の初期値はどちらも硬い拘束(コンプライアンス0)であり、旧経路の硬い距離拘束と同じ物性から始める。
//! 曲げは有限の柔らかさ(吊るし布は10毎ニュートンメートル、マントはcm相当スケールのため長さの2乗の比で1e-3)を与え、折れを抑えつつ垂れる布にする。見た目の硬さの判断はオーナーの実操作に委ねる。
//! 固定とアタッチと掴みは目標拘束であり(Issue #37)、粒子の逆質量は全粒子が物性のまま正である。

use blitz_render::{布の刻み幅, 布の自己衝突, 布定数, 布素材};
use blitz_sim::{コンプライアンス, 曲げのコンプライアンス};

use super::{attach, target_constraints, マント間隔, 一辺粒子数, 吊るし間隔, 布プリセット, 掴み写像, 総質量};
use crate::error::起動エラー;

/// 吊るし布の曲げのコンプライアンス(毎ニュートンメートル)。刻み依存量α̃=10×3600=3.6e4が有効逆慣性(約4e5)の1割であり、折れは抑えつつ自重で垂れる。
const 吊るし布の曲げのコンプライアンス: f32 = 10.0;
/// マントの曲げのコンプライアンス。マントは1単位約1センチメートルのスケールであり、曲げのコンプライアンスは長さの2乗に反比例するため吊るし布の値を1e4で割る。
const マントの曲げのコンプライアンス: f32 = 1.0e-3;

/// 吊るし布(判断56の既定検証シナリオ): 上端行を世界固定点の目標拘束で空中に固定した布が正対カメラの前(quad構図)に垂れる。
/// スキン・動く目標・カプセルを使わず、掴む/離す/床接触を最小の変数で見せる。寸法はquadスケール(約1m)。
pub(in crate::app) fn 吊るし布を構築する(刻み幅: 布の刻み幅) -> Result<(布素材, 布プリセット), 起動エラー> {
    let 仕様 = blitz_sim::布仕様::生成する(一辺粒子数, 吊るし間隔, 総質量, [-0.775, 1.5, 0.4])?;
    let データ = blitz_sim::布を生成する(&仕様)?;
    let 目標拘束 = target_constraints::上端行を固定し掴みの枠を持つ目標拘束を組む(&データ, Vec::new())?;
    let 定数 = 布定数 {
        重力: [0.0, -9.8, 0.0],
        粒子間隔: 吊るし間隔,
        グリッド原点: [-0.8, -0.05, -0.4],
        速度減衰: 0.99,
        自己衝突: 布の自己衝突::行う,
        刻み幅,
    };
    let 物性 = blitz_sim::布の物性::一様に生成する(
        コンプライアンス::硬い(),
        曲げのコンプライアンス::生成する(吊るし布の曲げのコンプライアンス)?,
    );
    let 素材 = super::material::布素材を組む(&データ, &物性, &目標拘束.バッチ, Vec::new(), 定数)?;
    let プリセット = 布プリセット {
        カプセル: None,
        掴み: 掴み写像 {
            中心: [0.0, 0.75, 0.4],
            横基底: [1.2, 0.0, 0.0],
            縦基底: [0.0, 0.75, 0.0],
        },
        掴みの目標拘束添字: 目標拘束.掴みの拘束添字,
    };
    Ok((素材, プリセット))
}

/// マント(fox限定): 布は32x32粒子・間隔3.2(幅約99)。重力はcm相当スケールの-980/s^2。上端行はスキン済み頂点を目標にした動く目標拘束である。
/// キャラ衝突はカプセル1本の近似で脚・首を覆えない(絵作りはドメイン表現層の課題としてM10以降)。
pub(in crate::app) fn マントを構築する(
    頂点一覧: &[blitz_render::頂点],
    刻み幅: 布の刻み幅,
) -> Result<(布素材, 布プリセット), 起動エラー> {
    let 仕様 = blitz_sim::布仕様::生成する(一辺粒子数, マント間隔, 総質量, [0.0, 0.0, 0.0])?;
    let mut データ = blitz_sim::布を生成する(&仕様)?;
    let アタッチ対応一覧 = attach::アタッチ先を選ぶ(頂点一覧, &データ.上端行の粒子添字一覧);
    attach::初期形状を整形する(&mut データ, 頂点一覧, &アタッチ対応一覧, マント間隔);
    let 目標拘束 = target_constraints::上端行を固定し掴みの枠を持つ目標拘束を組む(&データ, Vec::new())?;
    let 目標の更新対応一覧 = target_constraints::目標の更新対応を作る(&目標拘束.バッチ, &アタッチ対応一覧);
    let 定数 = 布定数 {
        重力: [0.0, -980.0, 0.0],
        粒子間隔: マント間隔,
        グリッド原点: [-51.0, 0.0, -51.0],
        速度減衰: 0.985,
        自己衝突: 布の自己衝突::行う,
        刻み幅,
    };
    let 物性 = blitz_sim::布の物性::一様に生成する(
        コンプライアンス::硬い(),
        曲げのコンプライアンス::生成する(マントの曲げのコンプライアンス)?,
    );
    let 素材 = super::material::布素材を組む(&データ, &物性, &目標拘束.バッチ, 目標の更新対応一覧, 定数)?;
    let プリセット = 布プリセット {
        カプセル: Some(([0.0, 45.0, -45.0], [0.0, 55.0, 45.0], 22.0)),
        掴み: 掴み写像 {
            中心: [0.0, 50.0, 0.0],
            横基底: [0.0, 0.0, -110.0],
            縦基底: [0.0, 70.0, 0.0],
        },
        掴みの目標拘束添字: 目標拘束.掴みの拘束添字,
    };
    Ok((素材, プリセット))
}
