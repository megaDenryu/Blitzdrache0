//! アタッチ先の選択(判断52): 布の上端行の各粒子に、Foxの背中のライン上の頂点を対応させる。
//! 方法: レスト頂点を体軸(z)で上端粒子数ぶんの帯に等分し、各帯でyが最大の頂点を選ぶ。
//! 帯に頂点が無い場合は直前の選択を引き継ぐ(Foxは体軸方向に頂点が連続するため実際には起こりにくい)。

pub(super) fn アタッチ先を選ぶ(頂点一覧: &[blitz_render::頂点], 上端行: &[u32]) -> Vec<[u32; 2]> {
    let (z最小, z最大) = 頂点一覧.iter().fold((f32::MAX, f32::MIN), |(最小, 最大), 頂点| {
        (最小.min(頂点.位置[2]), 最大.max(頂点.位置[2]))
    });
    let 帯数 = 上端行.len();
    let 帯幅 = (z最大 - z最小) / super::帯数を実数へ(帯数);
    let mut 帯ごとの最高: Vec<Option<u32>> = vec![None; 帯数];
    for (頂点添字, 頂点) in 頂点一覧.iter().enumerate() {
        let 帯 = 帯を求める(頂点.位置[2], z最小, 帯幅, 帯数);
        let 更新するか = match 帯ごとの最高[帯] {
            None => true,
            Some(既存) => 頂点.位置[1] > 頂点一覧[super::添字をusizeへ(既存)].位置[1],
        };
        if 更新するか {
            帯ごとの最高[帯] = u32::try_from(頂点添字).ok();
        }
    }
    let mut 対応一覧 = Vec::with_capacity(帯数);
    let mut 直前 = 0u32;
    for (帯, &布粒子) in 上端行.iter().enumerate() {
        let 先 = 帯ごとの最高[帯].unwrap_or(直前);
        直前 = 先;
        対応一覧.push([布粒子, 先]);
    }
    対応一覧
}

/// 布の初期形状を「アタッチ先(Foxの背中のライン)から真下へ垂らしたマント」に整形する。
/// アタッチパスは毎フレーム上端を目標位置へ移すため、初期形状が離れていると1フレームで大移動が起き、
/// 距離拘束の巨大補正が伝播して布が発散する(実測で確認した)。初期形状をアタッチ後の想定形に一致させて防ぐ。
pub(super) fn 初期形状を整形する(
    データ: &mut blitz_sim::布データ,
    頂点一覧: &[blitz_render::頂点],
    アタッチ対応一覧: &[[u32; 2]],
    間隔: f32,
) {
    let 一辺 = アタッチ対応一覧.len();
    for (列, 対応) in アタッチ対応一覧.iter().enumerate() {
        let 先 = 頂点一覧[super::添字をusizeへ(対応[1])].位置;
        for 行 in 0..一辺 {
            let 粒子添字 = 行 * 一辺 + 列;
            let 垂れ量 = 間隔 * super::帯数を実数へ(行);
            データ.粒子一覧[粒子添字].位置 = [先[0], 先[1] - 垂れ量, 先[2]];
        }
    }
}

/// z座標が属する帯を線形走査で求める(帯数は高々数十のため走査コストは無視できる)。
fn 帯を求める(z: f32, z最小: f32, 帯幅: f32, 帯数: usize) -> usize {
    if 帯幅 <= 0.0 {
        return 0;
    }
    for 帯 in 0..帯数 {
        let 帯上限 = z最小 + 帯幅 * super::帯数を実数へ(帯 + 1);
        if z < 帯上限 {
            return 帯;
        }
    }
    帯数 - 1
}
