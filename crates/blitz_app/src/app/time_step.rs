//! その描画で固定刻みを何本進めるかを決める配線。時間進行方針と、実行の種類で1度だけ選んだ進め方を1つに束ねて持ち、
//! 1フレーム実行へ「この描画で進める刻み数」と「その刻み数ぶんに進むゲームの時間」を答える。
//!
//! 束ねる範囲をここへ限るのは、固定刻みで確定するゲーム状態も、描画機会ごとの一時状態も、検収の計測もこの束の関心ではないためである。
//! ここが持つのは刻みの本数を決めるための状態だけであり、アプリはこの束を1つのフィールドとして持つ。
//! 参照: `_doc/設計/時間の規律.md`「判断3」「判断9」、Issue #31「アプリ構造体の所有状態を責務別の配線構造体へ整理する」。

mod accumulator;
#[cfg(test)]
mod accumulator_tests;
mod advance;
#[cfg(test)]
mod advance_tests;
mod policy;
mod tick_count;

pub(in crate::app) use policy::時間進行方針;
pub(crate) use tick_count::進める刻み数;

use blitz_math::秒;

use crate::cli::起動モード;

pub(in crate::app) struct 時間進行配線 {
    方針: 時間進行方針,
    進め方: advance::固定刻みの進め方,
}

impl 時間進行配線 {
    pub(in crate::app) fn 起動モードから作る(モード: 起動モード, 方針: 時間進行方針) -> Self {
        Self {
            方針,
            進め方: advance::固定刻みの進め方::起動モードから決める(モード),
        }
    }

    /// 1描画に1度だけ呼ぶ。無期限実行の枝はここでだけ実時間を読む。
    pub(in crate::app) fn この描画で進める刻み数を決める(&mut self) -> 進める刻み数 {
        self.進め方.この描画で進める刻み数を決める(&self.方針)
    }

    /// ゲーム更新の1刻みが何秒ぶんか。刻みを回す側がゲーム配線へ渡す。
    pub(in crate::app) fn 基本刻み(&self) -> 秒 {
        self.方針.基本刻み()
    }

    /// その描画で進めた刻み数ぶんに進むゲームの時間。アニメーション時刻と天空の進行がこの値へ追随する。
    pub(in crate::app) fn 刻み数ぶんの秒を求める(&self, 刻み数: 進める刻み数) -> 秒 {
        self.方針.刻み数ぶんの秒を求める(刻み数)
    }
}
