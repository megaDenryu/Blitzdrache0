//! その描画で固定刻みを何本進めるかを決める配線。時間進行の構成値と、実行の種類で1度だけ選んだ進め方と、今から描く
//! 描画機会の番号と、今から進める固定刻みの番号を1つに束ねて持ち、1フレーム実行へ「この描画で進める刻み数」と
//! 「その刻み数ぶんに進むゲームの時間」と「この描画機会の番号」と「この刻みの番号」を答える。描画機会の番号の保持と
//! 描画機会の総数との比較をここへ置くのは、どちらも描画機会を数える時間意味に属するためである
//! (参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断11」)。固定刻みの番号もここが所有し、刻みを回す工程が1本ごとに
//! 進める。遊ばない起動でも番号は進む(参照: 同「判断13」)。
//!
//! 束ねる範囲をここへ限るのは、固定刻みで確定するゲーム状態も、描画機会ごとの一時状態も、検収の計測もこの束の関心ではないためである。
//! ここが持つのは刻みの本数を決めるための状態だけであり、アプリはこの束を1つのフィールドとして持つ。
//! 参照: `_doc/設計/時間の規律.md`「判断3」「判断9」、Issue #31「アプリ構造体の所有状態を責務別の配線構造体へ整理する」。

