pub(in crate::app) struct 時間進行配線 {
    方針: 時間進行方針,
    進め方: advance::固定刻みの進め方,
    現在フレーム: フレーム番号, // 今から描く描画機会の番号。描き終えた描画機会が1つ進める
}

impl 時間進行配線 {
    pub(in crate::app) fn 起動モードから作る(モード: 起動モード, 方針: 時間進行方針) -> Self {
        Self {
            方針,
            進め方: advance::固定刻みの進め方::起動モードから決める(モード),
            現在フレーム: フレーム番号::起動時の最初(),
        }
    }

    /// 今から描く描画機会の番号。描画機会の途中で変わらないため、工程の先頭で1度読んで配る。
    pub(in crate::app) fn 現在のフレーム番号(&self) -> フレーム番号 {
        self.現在フレーム
    }

    /// 描画機会を1つ描き終えたときに1度だけ呼ぶ。番号を進め、フレーム数の決まった実行が最後の描画を終えたかを答える。
    /// 番号(序数)と総フレーム数(基数)の比較をここへ閉じ、呼び出し側が2つを算術で並べない。
    pub(in crate::app) fn 次のフレームへ進める(&mut self, モード: 起動モード) -> 描画機会の続き {
        self.現在フレーム = self.現在フレーム.次へ進める();
        let 総フレーム数 = match モード {
            起動モード::スモーク実行 { フレーム数 } | 起動モード::ベンチ実行 { フレーム数 } => フレーム数,
            起動モード::段差走査実行 { 走査指定 } => 走査指定.総フレーム数(),
            起動モード::無期限実行 => return 描画機会の続き::続ける,
        };
        if self.現在フレーム.総フレーム数に達したか(総フレーム数) {
            描画機会の続き::総フレーム数に達した
        } else {
            描画機会の続き::続ける
        }
    }

    /// 1描画に1度だけ呼ぶ。無期限実行の選択肢はここでだけ実時間を読む。
    /// 補間の割合を刻み数と同じ答えに含めるのは、割合が刻みを数え終えた後の余りから決まるためである。
    /// 順序をこの1箇所で決め、呼び出し側が2つの口を正しい順で叩く形にしない。
    pub(in crate::app) fn この描画の時間の進みを決める(&mut self) -> この描画の時間の進み {
        let 刻み数 = self.進め方.この描画で進める刻み数を決める(&self.方針);
        この描画の時間の進み::生成する(self.現在フレーム, 刻み数, self.進め方.この描画の補間の割合を求める(&self.方針))
    }

    /// ゲーム更新の1刻みが何秒ぶんか。刻みを回す側がゲーム配線へ渡す。
    pub(in crate::app) fn 基本刻み(&self) -> 秒 {
        self.方針.基本刻み()
    }

    /// その描画で進めた刻み数ぶんに進むゲームの時間。アニメーション時刻と天空の進行がこの値へ追随する。
    pub(in crate::app) fn 刻み数ぶんの秒を求める(&self, 刻み数: 進める刻み数) -> 秒 {
        self.方針.刻み数ぶんの秒を求める(刻み数)
    }
}
