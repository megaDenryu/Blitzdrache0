//! シーンごとの初期カメラ姿勢の引き当て。担当するのは、世界の種別からどの世界の構図を選ぶかと、
//! 起動指定のカメラのずれを最後に加えることだけである。構図そのものは世界ごとのモジュールが持つ。
//! 既定は`カメラ::生成する()`のままであり、構図を持たない世界はすべてそれになる。

mod fox_tour_view;
mod fox_view;
mod night_lights_view;
mod part_house_row_view;
mod prop_view;
mod shadow_view;
mod stone_hut_doorway_view;
mod terrain_origin_view;
mod vegetation_view;
mod village_view;
mod visual_sample_view;

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::メートル;

use crate::cli::{世界の種別, 地形世界の種別, 小物世界の種別, 平行移動起動設定};

pub(super) fn シーン初期カメラを作る(種別: 世界の種別, 配置: &平行移動起動設定) -> カメラ {
    let mut カメラ = カメラ::生成する();
    世界ごとの姿勢を与える(&mut カメラ, 種別);
    // 世界ごとの姿勢を決めた後に加える。姿勢の分岐が指定を打ち消さないため、指定した量がそのまま姿勢と視点の変化になる。
    カメラ.更新する(カメラインテント {
        ヨー差分: 配置.カメラ方位差分,
        ピッチ差分: 配置.カメラ俯角差分,
        距離倍率: 1.0,
    });
    カメラ.注視点をずらす(配置.カメラずれ, メートル::生成する(0.0), メートル::生成する(0.0));
    カメラ
}

fn 世界ごとの姿勢を与える(カメラ: &mut カメラ, 種別: 世界の種別) {
    match 種別 {
        世界の種別::影の検収世界 => shadow_view::姿勢を与える(カメラ),
        世界の種別::キツネ => fox_view::姿勢を与える(カメラ),
        世界の種別::植生の検収世界(_) => vegetation_view::姿勢を与える(カメラ),
        世界の種別::地形世界(地形世界の種別::起点) => terrain_origin_view::姿勢を与える(カメラ),
        世界の種別::地形世界(地形世界の種別::場所巡り) => fox_tour_view::姿勢を与える(カメラ),
        世界の種別::地形世界(地形世界の種別::目視見本) => visual_sample_view::姿勢を与える(カメラ),
        世界の種別::地形世界(地形世界の種別::夜灯り) => night_lights_view::姿勢を与える(カメラ),
        世界の種別::小物世界(小物世界の種別::集落) => village_view::姿勢を与える(カメラ),
        世界の種別::小物世界(小物世界の種別::石の小屋の屋内) => stone_hut_doorway_view::姿勢を与える(カメラ),
        世界の種別::小物世界(小物世界の種別::部品で組んだ家の並び) => part_house_row_view::姿勢を与える(カメラ),
        世界の種別::小物世界(小物世界の種別::名前で選ばれない小物) => prop_view::姿勢を与える(カメラ),
        世界の種別::平面板
        | 世界の種別::ヘルメット
        | 世界の種別::材質差し替えの検収世界
        | 世界の種別::間接照明の検収世界
        | 世界の種別::両視錐台外の群の検収世界
        | 世界の種別::二材質の検収世界
        | 世界の種別::テクスチャ圧縮の検収世界
        | 世界の種別::地形世界(地形世界の種別::名前で選ばれない地形)
        | 世界の種別::名前で選ばれない世界 => {}
    }
}
