//! シーンごとの初期カメラ姿勢。既定はカメラ::生成する()のまま(全シーン共通)だが、
//! シャドウ検証シーンだけは床(y=0)・遮蔽quad(y=1)・シャドウの落ち方を見下ろせるよう
//! 初期ピッチ・距離を調整する(判断37「カメラ距離を調整してよい」の適用箇所)。

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::{メートル, ラジアン};

use crate::cli::平行移動起動設定;

const シャドウシーン識別子: &str = "shadow_scene";
const フォックスシーン識別子: &str = "fox";
/// 地形世界の起動時シーン。この名前で起動したときだけ、地形の起伏が読み取れる俯瞰の初期姿勢にする。
const 地形起点シーン識別子: &str = "terrain_origin";
/// 植生インスタンスの検証シーン。この接頭辞で始まるシーンだけ、チャンク中央の群を見下ろす初期姿勢にする。
const 植生シーン接頭辞: &str = "vegetation";
/// 群が敷かれるチャンク中央の局所座標。チャンクの大域原点はX最小・Z最小の角にあるため、一辺100メートルの半分だけ内側である。
const 植生の注視点メートル: f32 = 50.0;

pub(super) fn シーン初期カメラを作る(シーン名: &str, 配置: &平行移動起動設定) -> カメラ {
    let mut カメラ = カメラ::生成する();
    if シーン名 == シャドウシーン識別子 {
        カメラ.更新する(カメラインテント {
            ヨー差分: ラジアン::度から(180.0),
            ピッチ差分: ラジアン::度から(50.0),
            距離倍率: 2.0,
        });
    }
    // Foxはモデルの寸法が大きい(体長約120単位)ため全身が入る距離まで引き、歩きが見える真横の構図にする。
    if シーン名 == フォックスシーン識別子 {
        カメラ.更新する(カメラインテント {
            ヨー差分: ラジアン::度から(90.0),
            ピッチ差分: ラジアン::度から(10.0),
            距離倍率: 45.0,
        });
    }
    // 地形世界は一辺100メートルのチャンクが5×5に並ぶ。距離150メートル・見下ろし35度にすると、
    // 視点は地表から約86メートル上に立ち、起伏の稜線が地平として画面に入る斜めの構図になる。
    // 距離を伸ばすほど視点は原点から離れ、視点位置がそのまま必要集合の中心になるため、
    // 先読み半径1で常駐する9チャンクの外側を見ることになる。この構図はその境目が地平に来る値である。
    if シーン名 == 地形起点シーン識別子 {
        カメラ.更新する(カメラインテント {
            ヨー差分: ラジアン::度から(0.0),
            ピッチ差分: ラジアン::度から(35.0),
            距離倍率: 50.0,
        });
    }
    // 植生の群は一辺24メートルの正方領域へ敷かれる。距離45メートル・見下ろし60度にすると、4個体が画面の4分割へ1体ずつ入り、
    // 中央で交わる帯には個体が掛からない。個体の高さ3メートルぶんの遠近のずれは中央から外へ向くため、帯を横切らない。
    if シーン名.starts_with(植生シーン接頭辞) {
        カメラ.更新する(カメラインテント {
            ヨー差分: ラジアン::度から(0.0),
            ピッチ差分: ラジアン::度から(60.0),
            距離倍率: 15.0,
        });
        カメラ.注視点をずらす(
            メートル::生成する(植生の注視点メートル),
            メートル::生成する(0.0),
            メートル::生成する(植生の注視点メートル),
        );
    }
    // シーンごとの姿勢を決めた後に加える。姿勢の分岐が指定を打ち消さないため、指定した量がそのまま姿勢と視点の変化になる。
    カメラ.更新する(カメラインテント {
        ヨー差分: 配置.カメラ方位差分,
        ピッチ差分: 配置.カメラ俯角差分,
        距離倍率: 1.0,
    });
    カメラ.注視点をずらす(配置.カメラずれ, メートル::生成する(0.0), メートル::生成する(0.0));
    カメラ
}
