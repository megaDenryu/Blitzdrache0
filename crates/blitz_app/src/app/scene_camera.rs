//! シーンごとの初期カメラ姿勢。既定はカメラ::生成する()のまま(全シーン共通)だが、
//! シャドウ検証シーンだけは床(y=0)・遮蔽quad(y=1)・シャドウの落ち方を見下ろせるよう
//! 初期ピッチ・距離を調整する(判断37「カメラ距離を調整してよい」の適用箇所)。

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::ラジアン;

const シャドウシーン識別子: &str = "shadow_scene";

pub(super) fn シーン初期カメラを作る(シーン名: &str) -> カメラ {
    let mut カメラ = カメラ::生成する();
    if シーン名 == シャドウシーン識別子 {
        カメラ.更新する(カメラインテント {
            ヨー差分: ラジアン::度から(180.0),
            ピッチ差分: ラジアン::度から(50.0),
            距離倍率: 2.0,
        });
    }
    カメラ
}
