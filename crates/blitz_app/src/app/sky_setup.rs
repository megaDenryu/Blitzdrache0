//! 固定時刻の空入力を組み立てる工程。受け取るのは空を描くかどうか、返すのはレンダラーへ毎フレーム渡す空入力である。
//!
//! 時刻はここで固定する。時計の進行と、方向光・環境光・露出を同じ天空状態へ配線することはOW5第3段が行うため、
//! この段は空パスが要る係数だけを1つの時刻から作り、既存シーンの絵を空の領域以外で変えない。
//! 空入力は視点にもフレームにも依存しないため、起動時に1度だけ作って毎フレーム同じ値を渡す。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「段階導入」

use std::fmt::Display;

use blitz_engine::sky::{天空状態を導出する, 空と太陽の方針, 空放射輝度係数};
use blitz_engine::time::世界時刻;
use blitz_math::大域秒;
use blitz_render::空入力;

/// 固定する世界時刻。既定の一日の長さでの朝9時であり、太陽高度が約35度で空の勾配と地表の陰影がどちらも読み取れる。
const 固定時刻の秒: f64 = 32_400.0;

pub(super) fn 固定時刻の空入力を作る(空有効: bool) -> Option<空入力> {
    if !空有効 {
        return None;
    }
    let 方針 = 空と太陽の方針::既定値();
    let 時刻 = 確定値(世界時刻::生成する(大域秒::生成する(固定時刻の秒)));
    let 状態 = 確定値(天空状態を導出する(時刻, &方針));
    let 係数 = 確定値(空放射輝度係数::導出する(&状態, &方針));
    Some(確定値(空入力::生成する(
        係数.方向係数(),
        係数.放射輝度スケール(),
        係数.夜空放射輝度().成分(),
        係数.昼係数().値(),
        状態.太陽方向().成分(),
        係数.太陽円盤放射輝度().成分(),
        係数.太陽円盤角半径(),
    )))
}

/// 入力が固定の定数だけであるため、ここでの失敗は定数か導出の不変条件が破れていることを意味する。
/// 起動時の設定不備ではないため型付きエラーへは載せず、破れた不変条件を示して停止する
/// (`scene_lighting`の検収用ライト方針と同じ扱い)。
fn 確定値<T, E: Display>(結果: Result<T, E>) -> T {
    結果.unwrap_or_else(|誤り| panic!("固定時刻の空入力の定数が不正だった: {誤り}"))
}
