//! アプリがディスクから実行時シーンを読んだ回数の記録。起動時シーンの読込とホットリロードの再読込を数える。
//! チャンクストリーミングの読込はこの数に入らない。あちらは読込器が別の経路で読み、ストリーミング要約が別に数えるためである。
//!
//! この数を持つのは、LODの段や可視判定の結果が変わってもディスクI/Oが起きないことを実行の外から見るためである。
//! 全段は束の読込時にGPUへ載っており、段の選択はファイルにもGPU確保にも触れない
//! (参照: `_doc/設計/植生インスタンスと物量計測.md`「ストリーミング統合」)。

#[derive(Default)]
pub(super) struct シーン読込計数 {
    総数: u64,
    /// 1フレーム目以降に起きた読込の数。起動時の読込はここに入らない。
    起動後: u64,
}

impl シーン読込計数 {
    /// 実行時シーンをディスクから読んだ直後に呼ぶ。`現在フレーム`が0なら起動時の読込として扱う。
    pub(super) fn 読み込んだ(&mut self, 現在フレーム: u32) {
        self.総数 += 1;
        if 現在フレーム > 0 {
            self.起動後 += 1;
        }
    }

    pub(super) fn 総数(&self) -> u64 {
        self.総数
    }

    pub(super) fn 起動後(&self) -> u64 {
        self.起動後
    }
}
