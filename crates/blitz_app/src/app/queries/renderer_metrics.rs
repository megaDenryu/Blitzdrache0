//! レンダラーだけを見て答える計器の照会。触れるのは`レンダラー`のフィールド1つだけであり、可視判定の配線にも
//! ストリーミングの配線にも触れない。
//!
//! レンダラーが未生成の間は1フレームも描いていないため、どの計器も`None`で答える。この分岐をここへ集めることで、
//! 呼び出し側の報告が「取得できない」場合の文言だけを持てばよくなる。

use blitz_render::indirect_lighting::焼き上げ本数の見込み;
use blitz_render::{
    GPUメモリ統計, レンダラー, 大気のベイク済み画像生成パス数の記録, 描画発行内訳, 材質資源表の要約, 検証カウンタ, 間接照明生成パス数の記録,
};

use crate::app::アプリ;

impl アプリ {
    /// 破棄後に読むための検証カウンタ。レンダラー未生成なら`None`(一度も描画していないためvalidationメッセージも発生し得ない)。
    pub(crate) fn 検証カウンタを取得する(&self) -> Option<検証カウンタ> {
        self.レンダラー.as_ref().map(レンダラー::検証カウンタを取得する)
    }

    pub(crate) fn gpuメモリ統計を取得する(&self) -> Option<GPUメモリ統計> {
        self.レンダラー.as_ref().map(レンダラー::gpuメモリ統計を取得する)
    }

    /// 最終フレームの描画発行内訳。レンダラー破棄前に呼ぶこと。
    pub(crate) fn 描画発行内訳を取得する(&self) -> Option<描画発行内訳> {
        self.レンダラー.as_ref().map(レンダラー::描画発行内訳を取得する)
    }

    /// 直近のフレームでscene系のセット番号ごとにディスクリプタセットを束縛した回数。レンダラー未生成なら`None`。
    pub(crate) fn セット別ディスクリプタ束縛回数を取得する(&self) -> Option<[u32; 4]> {
        self.レンダラー.as_ref().map(レンダラー::セット別ディスクリプタ束縛回数を取得する)
    }

    /// 公開中の資源表世代の版番号と中身の件数。レンダラー未生成なら表そのものが無いため`None`。
    pub(crate) fn 材質資源表の要約を取得する(&self) -> Option<材質資源表の要約> {
        self.レンダラー.as_ref().map(レンダラー::材質資源表の要約を取得する)
    }

    /// 大気のベイク済み画像生成パスの実行数の記録。レンダラー未生成なら1フレームも数えていないため`None`。
    pub(crate) fn 大気のベイク済み画像生成パス数の記録を取得する(
        &self,
    ) -> Option<&大気のベイク済み画像生成パス数の記録> {
        self.レンダラー.as_ref().map(レンダラー::大気のベイク済み画像生成パス数の記録を取得する)
    }

    /// 間接照明の表現を焼くパスの実行数の記録。レンダラー未生成なら1フレームも数えていないため`None`。
    pub(crate) fn 間接照明生成パス数の記録を取得する(&self) -> Option<&間接照明生成パス数の記録> {
        self.レンダラー.as_ref().map(レンダラー::間接照明生成パス数の記録を取得する)
    }

    /// 遠方環境の契約が1フレームに積む本数の見込み。レンダラー未生成のときと、契約が定数近似で資源を
    /// 持たないときのどちらも`None`になる。この2つを呼び出し側が区別できるのは、実測の記録が`Some`なら
    /// レンダラーは生成されているためである。
    pub(crate) fn 間接照明の焼き上げ本数の見込みを取得する(&self) -> Option<焼き上げ本数の見込み> {
        self.レンダラー.as_ref().and_then(レンダラー::間接照明の焼き上げ本数の見込みを取得する)
    }
}
