//! 起動設定から、その世界の描画の組み立て方を決める工程。受け取るのは起動設定と空を描くかどうか、
//! 返すのはフレーム段階の並びと局所可視性補正の描画設定と時間再構成の描画設定である。
//!
//! 3つを1つの値で返すのは、拡散間接方式と時間再構成方式がどちらもフレーム段階の並びへ条件を課すためである。
//! 局所可視性補正は深度プリパスが書いた深度を読むため、プリパスを積まない画面では深度が消去値のままになり、
//! 遮蔽の標本化は全画素を空と見て可視度1を返す。絵は破綻せず、ただ局所可視性補正が1画素も効かない。
//! 時間再構成は再構成後の色をHDR中間画像へ書くため、ポスト処理を組まない画面では書き先そのものが無い。
//! この2つの無言の食い違いを起こさないため、3つの決定を1つの工程に閉じる
//! (`参照: _doc/設計/放射輝度問い合わせ階層.md`「IIaの実装設計」・`_doc/設計/時間再構成.md`「判断d」)。

use blitz_engine::local_visibility::拡散間接方式;
use blitz_engine::temporal_reconstruction::{今のフレームの寄与率, 出現領域の相対許容, 時間再構成方式};
use blitz_render::local_visibility::{局所可視性の描画設定, 局所可視性の設定};
use blitz_render::temporal_reconstruction::時間再構成の描画設定;
use blitz_render::深度プリパス方式;

use crate::app::time_of_day::scene_policy::{世界の拡散間接方式を決める, 世界の時間再構成方式を決める};
use crate::cli::{起動引数エラー, 起動設定};
use crate::error::起動エラー;

/// 起動時に決まり、以降は変わらない世界の描画の組み立て方。
pub(in crate::app) struct 世界の描画構成 {
    pub(in crate::app) フレーム構成: blitz_render::フレーム構成,
    pub(in crate::app) 局所可視性の描画設定: 局所可視性の描画設定,
    pub(in crate::app) 時間再構成の描画設定: 時間再構成の描画設定, // 世界が宣言した方式と、パスが押し込む2つの数をGPU境界の型へ写した値。レンダラーの生成へそのまま渡る
}

pub(in crate::app) fn 決める(起動設定: &起動設定, 空を描くか: bool) -> Result<世界の描画構成, 起動エラー> {
    let 方式 = 世界の拡散間接方式を決める(起動設定.シーン.種別(), 起動設定.局所可視性);
    let 深度プリパス方式 = 深度プリパス方式を決める(方式, 起動設定.深度プリパス方式)?;
    let 時間再構成方式 = 世界の時間再構成方式を決める(起動設定.シーン.種別(), 起動設定.時間再構成);
    if 時間再構成方式 == 時間再構成方式::履歴混合 && !起動設定.ポスト処理有効 {
        return Err(起動引数エラー::時間再構成がポスト処理を要る.into());
    }
    Ok(世界の描画構成 {
        フレーム構成: blitz_engine::既定フレーム構成を作る(起動設定.ポスト処理有効, 空を描くか)
            .深度プリパス方式を据えた(深度プリパス方式),
        局所可視性の描画設定: 局所可視性の描画設定 {
            補正の設定: 局所可視性の設定::既定(),
            方式: 描画側の拡散間接方式へ写す(方式),
            検収の上書き: 起動設定.局所可視性.可視度の固定,
        },
        時間再構成の描画設定: 描画側の時間再構成の設定へ写す(時間再構成方式),
    })
}

/// そのフレーム構成が積む深度プリパスの方式。
///
/// 起動指定が無いときに拡散間接方式によらず`使い色は近いか同値で比べる`を選ぶのは、2026-08-08のオーナー裁定で
/// この方式を全世界の既定に定めたためである(参照: `_doc/設計/放射輝度問い合わせ階層.md`「既定をBへ切り替えた再裁定」)。
/// `使い色は等値で比べる`まで上げないのは、それが別個の性能最適化であり、既定として要る条件ではないためである。
/// 局所可視性補正を宣言した世界で明示の`--depth-prepass none`と重ねたときだけ失敗にするのは、深度の供給が
/// この補正の前提であり、かつ利用者が置いた明示の指定を黙って覆さないためである。
fn 深度プリパス方式を決める(
    方式: 拡散間接方式, 起動指定: Option<深度プリパス方式>
) -> Result<深度プリパス方式, 起動エラー> {
    match (方式, 起動指定) {
        (_, None) => Ok(深度プリパス方式::使い色は近いか同値で比べる),
        (拡散間接方式::局所可視性補正付き環境, Some(深度プリパス方式::使わない)) => {
            Err(起動引数エラー::局所可視性補正が深度プリパスを要る.into())
        }
        (_, Some(指定)) => Ok(指定),
    }
}

fn 描画側の拡散間接方式へ写す(方式: 拡散間接方式) -> blitz_render::local_visibility::拡散間接方式 {
    match 方式 {
        拡散間接方式::環境のみ => blitz_render::local_visibility::拡散間接方式::環境のみ,
        拡散間接方式::局所可視性補正付き環境 => {
            blitz_render::local_visibility::拡散間接方式::局所可視性補正付き環境
        }
    }
}

/// 混合の2つの数はCPU正本の既定値をそのまま開く。描画側に値の写しを置かないことが、
/// slangの写しとの一致検査を`crates/blitz_engine/src/temporal_reconstruction/constants.rs`1つへ向けさせる。
fn 描画側の時間再構成の設定へ写す(方式: 時間再構成方式) -> 時間再構成の描画設定 {
    時間再構成の描画設定 {
        方式: match 方式 {
            時間再構成方式::使わない => blitz_render::temporal_reconstruction::時間再構成方式::使わない,
            時間再構成方式::履歴混合 => blitz_render::temporal_reconstruction::時間再構成方式::履歴混合,
        },
        今のフレームの寄与率: 今のフレームの寄与率::既定().値(),
        出現領域の相対許容: 出現領域の相対許容::既定().値(),
    }
}
