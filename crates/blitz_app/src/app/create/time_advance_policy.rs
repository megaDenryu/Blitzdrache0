//! コンポジションルートが時間進行方針を組む場所。担当するのは「基本刻みと一描画で進める刻み数の上限を1つずつ選んで束ねる」
//! ことだけであり、刻みの回し方も蓄積の持ち方も知らない。
//!
//! 上限をここで選ぶのは、本数を刻みの繰り返しへ埋め込まないためである。初期値の4は推奨値であり、実測で2・6へ動かす。
//! 基本刻みをゲーム更新の一刻みの秒から受け取るのは、ゲームが1刻みで進める長さと、蓄積が1本と数える長さを
//! 別々の数として持たせないためである。
//! 参照: `_doc/設計/時間の規律.md`「判断1」「判断3」。

use super::super::time_step::{時間進行方針, 進める刻み数};
use crate::game::ゲーム更新の一刻みの秒;

/// 一描画で進める固定刻みの本数の上限の初期値。
const 一描画で進める刻み数の上限: u16 = 4;

pub(in crate::app) fn 時間進行方針を組む() -> 時間進行方針 {
    時間進行方針::生成する(ゲーム更新の一刻みの秒(), 進める刻み数::生成する(一描画で進める刻み数の上限))
}
