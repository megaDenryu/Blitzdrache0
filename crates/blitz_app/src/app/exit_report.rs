//! 終了時の報告を出す局面。呼ばれるのはプロセスの終わりに1回だけであり、毎フレーム呼ばれる描画とは呼び出し頻度も
//! 触れるフィールドも違う。担当するのは、各束から終了時の観測一式を1回だけ集めて`reports`へ渡すことと、
//! 布の参照比較の突き合わせを最後に頼むことである。行の整形と出す順序は`reports::exit_report`が持つ。
//!
//! 注意: レンダラー内部を読む報告(GPU時間・GPUメモリ・描画発行)は破棄より前に呼ぶ必要があるため、この局面は
//! `据え付けを破棄する`より前に1回だけ呼ぶ。

use super::screen_installation::画面の据え付け;

impl super::アプリ {
    pub(crate) fn 終了時報告を出す(&self) {
        let 観測 = self.終了時の観測一式を集める();
        crate::reports::exit_report::終了時報告を出す(&観測);
        self.布の配線.終了時に参照計算と突き合わせる(self.据え付け.as_ref().map(画面の据え付け::レンダラーを見る));
    }
}
