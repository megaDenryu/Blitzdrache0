//! engineの描画対象一覧をrenderの非空な描画シーン素材へ変換する。

use blitz_engine::{シーンデータ, 描画対象データ};
use blitz_render::{描画シーン素材, 描画対象素材};

use super::convert;
use crate::error::起動エラー;

pub(super) fn 変換する(シーン: &シーンデータ) -> Result<描画シーン素材, 起動エラー> {
    let mut 入力一覧 = シーン.描画対象一覧().iter();
    let 先頭 = match 入力一覧.next() {
        Some(描画対象) => 描画対象を変換する(描画対象)?,
        None => panic!("シーンデータは1つ以上の描画対象を持つ不変条件に違反した"),
    };
    let 残り = 入力一覧.map(描画対象を変換する).collect::<Result<Vec<_>, _>>()?;
    Ok(描画シーン素材::生成する(先頭, 残り))
}

fn 描画対象を変換する(描画対象: &描画対象データ) -> Result<描画対象素材, 起動エラー> {
    let メッシュ = 描画対象.メッシュ();
    let 頂点一覧 = メッシュ.頂点一覧.iter().map(convert::頂点変換する).collect();
    let マテリアル = convert::マテリアルを変換する(描画対象.マテリアル())?;
    Ok(描画対象素材::生成する(
        描画対象.ローカルからワールド(),
        頂点一覧,
        メッシュ.インデックス一覧.clone(),
        マテリアル,
    ))
}
