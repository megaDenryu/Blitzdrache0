//! blitz_engineのマテリアルデータ・メッシュ頂点属性を、blitz_renderのマテリアル素材・頂点へ変換する。

use blitz_engine::texture_storage::{テクスチャ格納形式, 格納済みテクスチャ};
use blitz_engine::{マテリアルデータ, メッシュデータ, 描画形状};
use blitz_render::{
    テクスチャ用途, テクスチャ素材, マテリアル素材, メッシュ素材, 詳細段メッシュ列, 金属粗さPBR素材
};

use crate::error::起動エラー;

/// 判断23: 用途(色か線形データか)を役割ごとに明示してから`マテリアル素材`を組み立てる。
/// 無いテクスチャをここで既定の画素へ置き換えないのは、レンダラーの材質テクスチャ表が「無し」を特徴ビットと
/// 正準フォールバックのスロットで表すためである。ここで埋めると同じ既定画素が材質の数だけ常駐する
/// (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「材質レコードとテクスチャ台帳」)。
pub(super) fn マテリアルを変換する(データ: &マテリアルデータ) -> Result<マテリアル素材, 起動エラー> {
    let マテリアルデータ::金属粗さPBR(データ) = データ;
    Ok(マテリアル素材::金属粗さPBR(金属粗さPBR素材::生成する(
        テクスチャを変換する(データ.ベースカラー.as_ref(), テクスチャ用途::色)?,
        テクスチャを変換する(データ.金属粗さ.as_ref(), テクスチャ用途::線形データ)?,
        テクスチャを変換する(データ.法線マップ.as_ref(), テクスチャ用途::線形データ)?,
        データ.ベースカラー係数,
        データ.金属度係数,
        データ.粗さ係数,
    )?))
}

/// 実行時形式が運ぶ格納済みテクスチャを、レンダラーのテクスチャ素材へ写す。段の並びは両側が同じ規則で検査するため、
/// ここは形式の枝の対応付けと段のバイト列の受け渡しだけを行う。
fn テクスチャを変換する(
    データ: Option<&格納済みテクスチャ>,
    用途: テクスチャ用途,
) -> Result<Option<テクスチャ素材>, 起動エラー> {
    let Some(データ) = データ else {
        return Ok(None);
    };
    Ok(Some(テクスチャ素材::生成する(
        データ.幅を返す(),
        データ.高さを返す(),
        格納形式を写す(データ.格納形式を返す()),
        データ.段ごとのバイト列を返す().to_vec(),
        用途,
    )?))
}

/// エンジンとレンダラーが同じ語彙の別の型を持つのは、レンダラーがblitz_engineを知らないためである。
/// 枝を足したときに写し忘れないよう、網羅的な照合でここ1箇所に写像を置く。
fn 格納形式を写す(格納形式: テクスチャ格納形式) -> blitz_render::テクスチャ格納形式 {
    match 格納形式 {
        テクスチャ格納形式::RGBA8 => blitz_render::テクスチャ格納形式::RGBA8,
        テクスチャ格納形式::BC1 => blitz_render::テクスチャ格納形式::BC1,
    }
}

/// 形状の判別はエンジン側の語彙であり、レンダラーは詳細段の列だけを受け取る。段の有無で描画の手順が変わらないためである。
pub(super) fn 形状を変換する(形状: &描画形状) -> 詳細段メッシュ列 {
    let mut 段一覧 = 形状.全メッシュ().iter().map(メッシュを変換する);
    let 最詳細段 = match 段一覧.next() {
        Some(メッシュ) => メッシュ,
        None => panic!("描画形状は1段以上のメッシュを持つ不変条件に違反した"),
    };
    詳細段メッシュ列::生成する(最詳細段, 段一覧.collect())
}

fn メッシュを変換する(メッシュ: &メッシュデータ) -> メッシュ素材 {
    メッシュ素材::生成する(メッシュ.頂点一覧.iter().map(頂点変換する).collect(), メッシュ.インデックス一覧.clone())
}

fn 頂点変換する(属性: &blitz_engine::メッシュ頂点属性) -> blitz_render::頂点 {
    blitz_render::頂点 {
        位置: 属性.位置,
        法線: 属性.法線,
        接線: 属性.接線,
        uv: 属性.uv,
    }
}
