//! blitz_engineのマテリアルデータ・メッシュ頂点属性を、blitz_renderのマテリアル素材・頂点へ変換する。

use blitz_engine::{
    マテリアルデータ, メッシュデータ, 描画形状, 法線マップ既定テクスチャを作る, 白テクスチャデータを作る
};
use blitz_render::{テクスチャ用途, マテリアル素材, メッシュ素材, 詳細段メッシュ列, 金属粗さPBR素材};

use crate::error::起動エラー;

/// 判断23: 無いテクスチャへ既定素材(白・MR白・既定法線)を明示適用してから
/// `マテリアル素材`を組み立てる(無言のデフォルト適用の禁止)。
pub(super) fn マテリアルを変換する(データ: &マテリアルデータ) -> Result<マテリアル素材, 起動エラー> {
    let マテリアルデータ::金属粗さPBR(データ) = データ;
    let ベースカラー元 = データ.ベースカラー.clone().unwrap_or_else(白テクスチャデータを作る);
    let 金属粗さ元 = データ.金属粗さ.clone().unwrap_or_else(白テクスチャデータを作る);
    let 法線マップ元 = データ.法線マップ.clone().unwrap_or_else(法線マップ既定テクスチャを作る);

    let ベースカラー =
        blitz_render::テクスチャ素材::生成する(ベースカラー元.幅, ベースカラー元.高さ, ベースカラー元.rgba8, テクスチャ用途::色)?;
    let 金属粗さ = blitz_render::テクスチャ素材::生成する(金属粗さ元.幅, 金属粗さ元.高さ, 金属粗さ元.rgba8, テクスチャ用途::線形データ)?;
    let 法線マップ =
        blitz_render::テクスチャ素材::生成する(法線マップ元.幅, 法線マップ元.高さ, 法線マップ元.rgba8, テクスチャ用途::線形データ)?;

    Ok(マテリアル素材::金属粗さPBR(金属粗さPBR素材::生成する(
        ベースカラー,
        金属粗さ,
        法線マップ,
        データ.ベースカラー係数,
        データ.金属度係数,
        データ.粗さ係数,
    )?))
}

/// 形状の判別はエンジン側の語彙であり、レンダラーは詳細段の列だけを受け取る。段の有無で描画の手順が変わらないためである。
pub(super) fn 形状を変換する(形状: &描画形状) -> 詳細段メッシュ列 {
    let mut 段一覧 = 形状.全メッシュ().iter().map(メッシュを変換する);
    let 最詳細段 = match 段一覧.next() {
        Some(メッシュ) => メッシュ,
        None => panic!("描画形状は1段以上のメッシュを持つ不変条件に違反した"),
    };
    詳細段メッシュ列::生成する(最詳細段, 段一覧.collect())
}

fn メッシュを変換する(メッシュ: &メッシュデータ) -> メッシュ素材 {
    メッシュ素材::生成する(メッシュ.頂点一覧.iter().map(頂点変換する).collect(), メッシュ.インデックス一覧.clone())
}

fn 頂点変換する(属性: &blitz_engine::メッシュ頂点属性) -> blitz_render::頂点 {
    blitz_render::頂点 {
        位置: 属性.位置,
        法線: 属性.法線,
        接線: 属性.接線,
        uv: 属性.uv,
    }
}
