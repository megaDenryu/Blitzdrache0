//! 実行時形式のマテリアルデータを、レンダラーのマテリアル素材へ写す工程。触れるのは材質1件の中身だけであり、
//! メッシュと形状の写しには触れない。
//!
//! 材質の枝ごとに要る材料が違うことをここが引き受ける。標準金属粗さPBRはシーンが運ぶテクスチャだけで足りるが、
//! 地表の層の重ね合わせは世界に1つの地表層テクスチャ集から層のタイルを借りる。

use blitz_engine::{マテリアルデータ, 地表の層の重ね合わせデータ, 金属粗さPBRデータ};
use blitz_render::{テクスチャ用途, マテリアル素材, 地表の層の重ね合わせ素材, 金属粗さPBR素材};

use super::super::surface_layer_tiles::地表の層のタイル一式;
use super::{テクスチャを変換する, 格納済みテクスチャを変換する};
use crate::error::起動エラー;

/// 判断23: 用途(色か線形データか)を役割ごとに明示してから`マテリアル素材`を組み立てる。
/// 無いテクスチャをここで既定の画素へ置き換えないのは、レンダラーの材質テクスチャ表が「無し」を特徴ビットと
/// 正準フォールバックのスロットで表すためである。ここで埋めると同じ既定画素が材質の数だけ常駐する
/// (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「材質レコードとテクスチャ台帳」)。
pub(in crate::app::scene_load) fn マテリアルを変換する(
    データ: &マテリアルデータ,
    タイル: &地表の層のタイル一式,
) -> Result<マテリアル素材, 起動エラー> {
    match データ {
        マテリアルデータ::金属粗さPBR(データ) => 金属粗さpbrを変換する(データ),
        マテリアルデータ::地表の層の重ね合わせ(データ) => 地表の層の重ね合わせを変換する(データ, タイル),
    }
}

fn 金属粗さpbrを変換する(データ: &金属粗さPBRデータ) -> Result<マテリアル素材, 起動エラー> {
    Ok(マテリアル素材::金属粗さPBR(金属粗さPBR素材::生成する(
        テクスチャを変換する(データ.ベースカラー.as_ref(), テクスチャ用途::色)?,
        テクスチャを変換する(データ.金属粗さ.as_ref(), テクスチャ用途::線形データ)?,
        テクスチャを変換する(データ.法線マップ.as_ref(), テクスチャ用途::線形データ)?,
        データ.ベースカラー係数,
        データ.金属度係数,
        データ.粗さ係数,
    )?))
}

/// 重みはチャンクのシーンが運び、層のタイルは世界に1つの共有アセットから借りる。この工程が両者を1つの素材へ結ぶ段である。
/// 重みを線形データとして読むのは、4つの成分が色ではなく混ぜ合わせの割合だからである。
fn 地表の層の重ね合わせを変換する(
    データ: &地表の層の重ね合わせデータ,
    タイル: &地表の層のタイル一式,
) -> Result<マテリアル素材, 起動エラー> {
    Ok(マテリアル素材::地表の層の重ね合わせ(地表の層の重ね合わせ素材::生成する(
        格納済みテクスチャを変換する(データ.重みテクスチャ(), テクスチャ用途::線形データ)?,
        タイル.層ごとのタイル()?,
        データ.層ごとのタイル倍率(),
        データ.金属度係数(),
        データ.粗さ係数(),
    )?))
}
