//! 段Cの読み手を模した検査。シーンデータと描画シーン素材を捨てた後に、台帳の描画束だけからインデックス区間と材質束縛へ到達できることを見る。
//!
//! 起動時のシーンはレンダラーへ渡した後にスキンとアニメーションへ分解され、チャンクのシーンもGPU転送の完了とともに破棄される。
//! したがって描画発行の時点で残っているのは台帳の描画束だけである。プリミティブ添字と材質集合の中の割当添字しか持たない描画束では、
//! この時点で指す先が両方とも消えており、ここで見ている値を作れない。

use blitz_math::大域ワールド位置;

use super::tray_fixture::{シーンを作る, 描画対象を作る, 束座標};
use super::変換する;
use crate::app::draw_bundle_registry::描画束台帳;

/// 台帳へ入れた後にシーンと描画シーン素材を捨て、描画発行の時点に残っているものだけを読む。
#[test]
fn シーンを捨てた後も台帳の描画束から区間と材質束縛へ到達できる() {
    let 束id = blitz_render::描画束ID::生成する(7);
    let mut 台帳 = 描画束台帳::default();
    {
        let シーン = シーンを作る(vec![描画対象を作る(1, &[0, 5])]);
        let Ok(入力) = 変換する(&シーン, crate::cli::描画対象の並べ方::そのまま読む(), 束座標, 大域ワールド位置::原点())
        else {
            panic!("二材質の描画対象を変換できなかった");
        };
        台帳.束を登録する(束id, 入力.登録一式.描画束一覧);
        drop(入力.描画シーン);
        drop(シーン);
    }
    let Some(一覧) = 台帳.束の描画束(束id) else {
        panic!("登録した束の描画束を台帳から読めなかった");
    };
    let [前, 後] = 一覧.一覧() else {
        panic!("2プリミティブの描画対象で描画束が2件にならなかった: {}件", 一覧.件数());
    };
    assert_eq!(前.描画範囲().インデックス開始(), 0);
    assert_eq!(前.描画範囲().インデックス数(), 3);
    assert_eq!(前.描画範囲().頂点基準(), 0);
    assert_eq!(後.描画範囲().インデックス開始(), 3);
    assert_eq!(後.描画範囲().インデックス数(), 3);
    assert_eq!(後.描画範囲().頂点基準(), 2);
    assert_eq!(後.材質束縛().描画対象添字(), 0);
    // 対照: 破棄後に残るのは材質集合の割当順の添字(スロット5は2件目のため1)ではなく、原型が所有するスロット番号5である。
    assert_eq!(後.材質束縛().材質スロット().番号を返す(), 5);
}

/// 束を解除した後の台帳は同じ束IDで何も返さない。レンダラーが描かなくなった束の描画束が残ると、存在しない描画対象の発行を作る。
#[test]
fn 解除した束の描画束は台帳から読めない() {
    let 束id = blitz_render::描画束ID::生成する(7);
    let mut 台帳 = 描画束台帳::default();
    let シーン = シーンを作る(vec![描画対象を作る(1, &[0, 5])]);
    let Ok(入力) = 変換する(&シーン, crate::cli::描画対象の並べ方::そのまま読む(), 束座標, 大域ワールド位置::原点())
    else {
        panic!("二材質の描画対象を変換できなかった");
    };
    台帳.束を登録する(束id, 入力.登録一式.描画束一覧);
    台帳.束を解除する(束id);
    assert!(台帳.束の描画束(束id).is_none());
}
