//! 参照スロットからの材質解決の検査。最小スロットの材質を無条件に選ぶ実装では通らない材料を使う。

use blitz_engine::{
    マテリアルデータ, メッシュデータ, メッシュプリミティブ, メッシュ頂点属性, 描画形状, 材質スロットID, 材質スロット割当, 材質集合, 金属粗さPBRデータ,
};

use super::error::描画入力エラー;
use super::material_resolve::参照材質を解決する;

/// スロット0とスロット1に別々の材質を割り当てた集合。金属度係数だけを見ればどちらが選ばれたか分かる。
fn 二材質の集合() -> 材質集合 {
    let 割当 = |番号: u32, 金属度係数: f32| 材質スロット割当 {
        スロット: 材質スロットID::生成する(番号),
        マテリアル: マテリアルデータ::金属粗さPBR(金属粗さPBRデータ {
            ベースカラー: None,
            金属粗さ: None,
            法線マップ: None,
            ベースカラー係数: [1.0, 1.0, 1.0, 1.0],
            金属度係数,
            粗さ係数: 1.0,
        }),
    };
    match 材質集合::生成する(vec![割当(0, 0.25), 割当(1, 0.75)]) {
        Ok(値) => 値,
        Err(誤り) => panic!("検査用の二材質の集合を作れなかった: {誤り}"),
    }
}

fn 形状を作る(スロット番号一覧: &[u32]) -> 描画形状 {
    let プリミティブ列 = スロット番号一覧
        .iter()
        .map(|番号| メッシュプリミティブ {
            インデックス開始: 0,
            インデックス数: 1,
            頂点基準: 0,
            材質スロット: 材質スロットID::生成する(*番号),
        })
        .collect();
    描画形状::通常メッシュ(メッシュデータ {
        頂点一覧: vec![メッシュ頂点属性 {
            位置: [0.0, 0.0, 0.0],
            法線: [0.0, 1.0, 0.0],
            接線: [1.0, 0.0, 0.0, 1.0],
            uv: [0.0, 0.0],
        }],
        インデックス一覧: vec![0],
        スキン頂点属性一覧: None,
        プリミティブ列,
    })
}

/// スロット0が未使用でプリミティブがスロット1だけを参照する正規のデータ。最小スロットを選ぶ実装では0.25が返り、この検査は落ちる。
#[test]
fn 未使用の最小スロットを飛ばして参照スロットの材質を選ぶ() {
    let 集合 = 二材質の集合();
    let Ok(マテリアルデータ::金属粗さPBR(材質)) = 参照材質を解決する(&形状を作る(&[1]), &集合) else {
        panic!("参照スロットが1種類の形状で材質を解決できなかった");
    };
    assert_eq!(材質.金属度係数, 0.75);
}

#[test]
fn 参照スロットが1種類なら最小スロットでも同じ経路で解決する() {
    let 集合 = 二材質の集合();
    let Ok(マテリアルデータ::金属粗さPBR(材質)) = 参照材質を解決する(&形状を作る(&[0]), &集合) else {
        panic!("参照スロットが1種類の形状で材質を解決できなかった");
    };
    assert_eq!(材質.金属度係数, 0.25);
}

#[test]
fn 二種類のスロットを参照する描画対象を拒む() {
    let 集合 = 二材質の集合();
    let Err(描画入力エラー::プリミティブ別材質描画未対応 { スロット種類数 }) = 参照材質を解決する(&形状を作る(&[0, 1]), &集合)
    else {
        panic!("2種類のスロットを参照する形状が拒まれなかった");
    };
    assert_eq!(スロット種類数, 2);
}

#[test]
fn 材質集合に無いスロットの参照を拒む() {
    let 集合 = 二材質の集合();
    let Err(描画入力エラー::材質スロット未定義 { 番号 }) = 参照材質を解決する(&形状を作る(&[3]), &集合) else {
        panic!("材質集合に無いスロットの参照が拒まれなかった");
    };
    assert_eq!(番号, 3);
}
