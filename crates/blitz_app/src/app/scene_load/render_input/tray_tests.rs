//! 束の描画入力の検査。複数材質の描画対象がプリミティブごとのプリミティブ描画項目になり、そのすべてが1つの可視個体区間を共有すること、
//! 描画対象の件数と可視判定の材料が材質数で増えないこと、単一材質の描画対象では従来どおり束が1件であることを見る。

use blitz_engine::描画対象データ;

use super::tray_fixture::{シーンを作る, 二材質の集合, 描画対象を作る, 束座標};
use super::{変換する, 描画入力エラー, 束の描画入力};
use crate::error::起動エラー;

fn 変換して取り出す(描画対象一覧: Vec<描画対象データ>) -> Result<束の描画入力, 起動エラー> {
    変換する(
        &シーンを作る(描画対象一覧),
        crate::cli::描画対象の並べ方::そのまま読む(),
        束座標,
        super::検査用の材料(&super::検査用の地表の層のタイル()),
    )
}

/// 検収: 2材質の描画対象が2プリミティブぶんのプリミティブ描画項目になり、両者が同じ可視個体区間を共有する。
/// 描画対象数と可視判定の材料はプリミティブ数で増えず、可視選別が個体・原型・詳細段について1回だけであることを保つ。
#[test]
fn 二材質の描画対象が二つの束になり可視個体区間を共有する() {
    let Ok(入力) = 変換して取り出す(vec![描画対象を作る(1, &[0, 5])]) else {
        panic!("二材質の描画対象を変換できなかった");
    };
    let [前, 後] = 入力.登録一式.プリミティブ描画項目一覧.一覧() else {
        panic!(
            "2プリミティブの描画対象でプリミティブ描画項目が2件にならなかった: {}件",
            入力.登録一式.プリミティブ描画項目一覧.件数()
        );
    };
    assert_eq!(前.描画片().プリミティブ添字(), 0);
    assert_eq!(後.描画片().プリミティブ添字(), 1);
    assert_eq!(前.描画片().材質スロット().番号を返す(), 0);
    assert_eq!(後.描画片().材質スロット().番号を返す(), 5);
    assert_ne!(前.材質束縛(), 後.材質束縛());
    assert_eq!(前.可視個体区間(), 後.可視個体区間());
    assert_eq!(入力.描画シーン.描画対象数(), 1);
    assert_eq!(入力.登録一式.可視材料一覧.len(), 0);
}

/// 単一材質の描画対象は従来どおりプリミティブ描画項目が1件であり、その1件が唯一のスロットを指す。
#[test]
fn 単一材質の描画対象の束は一件のまま() {
    let Ok(入力) = 変換して取り出す(vec![描画対象を作る(1, &[0])]) else {
        panic!("単一材質の描画対象を変換できなかった");
    };
    let [唯一] = 入力.登録一式.プリミティブ描画項目一覧.一覧() else {
        panic!(
            "1プリミティブの描画対象でプリミティブ描画項目が1件にならなかった: {}件",
            入力.登録一式.プリミティブ描画項目一覧.件数()
        );
    };
    assert_eq!(唯一.描画片().プリミティブ添字(), 0);
    assert_eq!(唯一.描画片().材質スロット().番号を返す(), 0);
    assert_eq!(唯一.可視個体区間().描画対象添字(), 0);
    assert_eq!(入力.描画シーン.描画対象数(), 1);
}

/// プリミティブ描画項目の可視個体区間参照は束の中での描画対象の並び順を指す。別の描画対象の束は別の区間を指す。
#[test]
fn 描画対象ごとに別の可視個体区間を指す() {
    let Ok(入力) = 変換して取り出す(vec![描画対象を作る(1, &[0, 5]), 描画対象を作る(2, &[5])]) else {
        panic!("2つの描画対象を持つシーンを変換できなかった");
    };
    let 区間一覧: Vec<usize> = 入力
        .登録一式
        .プリミティブ描画項目一覧
        .一覧()
        .iter()
        .map(|束| 束.可視個体区間().描画対象添字())
        .collect();
    assert_eq!(区間一覧, vec![0, 0, 1]);
}

#[test]
fn 材質集合に無いスロットを参照する描画対象を拒む() {
    let Err(起動エラー::描画入力不正(描画入力エラー::プリミティブ描画項目の組み立て(誤り))) = 変換して取り出す(vec![描画対象を作る(1, &[3])])
    else {
        panic!("材質集合に無いスロットの参照が拒まれなかった");
    };
    assert_eq!(誤り.to_string(), "描画対象のプリミティブが参照する材質スロットID 3が材質集合に無い");
}

/// レンダラーへは代表の1材質でなく全スロットの材質が渡る。未使用スロットも落とさず、番号がそのまま保たれる。
#[test]
fn 材質集合の全スロットがスロット番号のまま渡る() {
    let Ok(一覧) = super::material_slots::変換する(&二材質の集合(), &super::検査用の地表の層のタイル()) else {
        panic!("二材質の集合を材質スロット素材一覧へ変換できなかった");
    };
    let 番号一覧: Vec<u32> = 一覧.一覧().iter().map(blitz_render::材質スロット素材::スロット番号).collect();
    assert_eq!(番号一覧, vec![0, 5]);
}
