//! 描画対象の形状から個体変換列を組み立てる工程。受け取るのは形状とアンカー基準の静的変換、返すのは個体ごとの変換列である。
//! インスタンス群の個体配置は原型のローカル空間から群のローカル空間への変換であり、これへ描画対象自身の
//! ローカルからアンカーへの変換を合成すると、個体1件のアンカー基準の変換になる。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「座標系」

use blitz_engine::描画形状;
use blitz_math::{ローカル, ワールド, 変換};
use blitz_render::個体変換列;

pub(super) fn 組み立てる(形状: &描画形状, ローカルからワールド: 変換<ローカル, ワールド>) -> 個体変換列 {
    let 描画形状::インスタンス群(群) = 形状 else {
        return 個体変換列::生成する(ローカルからワールド, Vec::new());
    };
    let mut 反復 = 群.配置一覧().iter().map(|配置| 配置.変換を作る().合成する(ローカルからワールド));
    let 先頭 = match 反復.next() {
        Some(変換) => 変換,
        None => panic!("インスタンス群は1つ以上の配置を持つ不変条件に違反した"),
    };
    個体変換列::生成する(先頭, 反復.collect())
}
