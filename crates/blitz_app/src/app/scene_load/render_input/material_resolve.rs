//! 描画へ渡す材質を、形状のプリミティブが参照する材質スロットから解決する工程。受け取るのは形状と材質集合、返すのは1つの材質である。
//!
//! プリミティブ別の材質描画はマルチマテリアルの段Bと段Cで解禁するため、それまでは参照スロットが2種類以上の描画対象をここで型付きエラーにして拒む。
//! 最小スロットの材質を無条件に選ぶと2つの誤りが起こる。段Aが正規に受理する複数材質のシーンを無言で1材質へ縮退させること、
//! および未使用スロットを許す契約のもとで最小スロットが未使用のときに、どのプリミティブも塗らない材質を選ぶことである。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「段階導入」

use blitz_engine::{マテリアルデータ, 描画形状, 材質スロットID, 材質集合};

use super::error::描画入力エラー;

pub(super) fn 参照材質を解決する<'材質>(
    形状: &描画形状,
    材質集合: &'材質 材質集合,
) -> Result<&'材質 マテリアルデータ, 描画入力エラー> {
    let 参照スロット一覧 = 参照スロットを集める(形状);
    let [スロット] = 参照スロット一覧[..] else {
        return Err(描画入力エラー::プリミティブ別材質描画未対応 {
            スロット種類数: 参照スロット一覧.len(),
        });
    };
    材質集合.材質を参照する(スロット).ok_or(描画入力エラー::材質スロット未定義 {
        番号: スロット.番号を返す()
    })
}

/// 全LOD段の全プリミティブが参照するスロットを重複なく集める。段ごとにプリミティブ数が違ってよいため、1段だけを見ることはできない。
fn 参照スロットを集める(形状: &描画形状) -> Vec<材質スロットID> {
    let mut 一覧: Vec<材質スロットID> = Vec::new();
    for メッシュ in 形状.全メッシュ() {
        for プリミティブ in &メッシュ.プリミティブ列 {
            if !一覧.contains(&プリミティブ.材質スロット) {
                一覧.push(プリミティブ.材質スロット);
            }
        }
    }
    一覧
}
