//! 描画束が載るチャンク座標から描画アンカーを導き出す工程。
//! 受け取るのはシーンと束のチャンク座標と世界全体の平行移動であり、返すのは描画アンカーの大域位置である。
//! 導出の前にシーン内の全描画対象が束と同じ所有チャンクに属することを確かめるため、所有チャンクの違う対象が同居しても無言で1つのアンカーへ丸められない。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「適用点: チャンク由来の描画アンカー」

use blitz_engine::{シーンデータ, チャンク座標};
use blitz_math::{大域メートル, 大域ワールド位置};

use crate::error::起動エラー;

/// 格子の一辺はチャンクストリーミングの格子が所有する。同じ値を2箇所で持つと配置とチャンク判定が食い違うため、ここは参照だけを行う。
fn 格子の一辺() -> 大域メートル {
    大域メートル::生成する(crate::app::streaming::一辺メートル)
}

pub(super) fn 導出する(
    シーン: &シーンデータ,
    束座標: チャンク座標,
    大域平行移動: 大域ワールド位置,
) -> Result<大域ワールド位置, 起動エラー> {
    for 描画対象 in シーン.描画対象一覧() {
        if 描画対象.所有チャンク() != 束座標 {
            return Err(起動エラー::描画対象の所有チャンク不一致(
                描画対象.所有チャンク(),
                束座標,
            ));
        }
    }
    Ok(束座標.大域原点を求める(格子の一辺()).平行移動する(大域平行移動))
}
