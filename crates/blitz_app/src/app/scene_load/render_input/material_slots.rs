//! 描画対象の材質集合を、レンダラーが材質スロット番号で引ける素材の一覧へ写す工程。受け取るのは材質集合、返すのは非空の一覧である。
//!
//! 代表を1つ選ばずに全スロットを渡すのは、描画発行がプリミティブごとに材質を指し、どのスロットも実際に束縛されうるためである。
//! スロット番号を並びの添字で代用しないのは、未使用スロットを許す契約のもとで番号が飛びうるためである。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「束縛バックエンドの移行境界」

use blitz_engine::材質集合;
use blitz_render::{材質スロット素材, 材質スロット素材一覧};

use super::super::surface_layer_tiles::地表の層のタイル一式;
use super::convert;
use crate::error::起動エラー;

pub(super) fn 変換する(
    材質集合: &材質集合, 地表の層のタイル: &地表の層のタイル一式
) -> Result<材質スロット素材一覧, 起動エラー> {
    let mut 素材一覧 = Vec::with_capacity(材質集合.件数());
    for 割当 in 材質集合.割当一覧() {
        let マテリアル = convert::マテリアルを変換する(&割当.マテリアル, 地表の層のタイル)?;
        素材一覧.push(材質スロット素材::生成する(割当.スロット.番号を返す(), マテリアル));
    }
    let mut 反復 = 素材一覧.into_iter();
    let 先頭 = match 反復.next() {
        Some(素材) => 素材,
        None => panic!("材質集合は1件以上の材質を持つ不変条件に違反した"),
    };
    Ok(材質スロット素材一覧::生成する(先頭, 反復.collect()))
}
