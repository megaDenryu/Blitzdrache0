//! 描画対象の格子配置が固定カメラに対して対称かを検査する。

use blitz_math::{メートル, ワールド, 位置};

use super::layout;

#[test]
fn 二対象はx軸の左右へ対称に配置される() {
    let 原点 = 位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0));
    let 左 = layout::配置する(0, 2).適用する(原点);
    let 右 = layout::配置する(1, 2).適用する(原点);
    assert!((左.x().値() + 右.x().値()).abs() < 0.0001);
    assert!(左.x().値() < 0.0);
    assert!(右.x().値() > 0.0);
    assert!(左.y().値().abs() < 0.0001);
    assert!(右.y().値().abs() < 0.0001);
}
