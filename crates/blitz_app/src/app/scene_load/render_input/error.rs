//! 束の描画入力を組み立てるときの失敗型。所有チャンクの照合という、この層だけが持つ条件をここが所有する。
//! 起動全体の失敗型へ直接足さないのは、層ごとの語彙を1つの列挙へ集めると、どの層が何を拒むのかが読めなくなるためである。
//! プリミティブと材質集合の対応はエンジン側のプリミティブ描画項目の組み立て工程が拒むため、その失敗は透過して運ぶ。

use blitz_engine::primitive_draw_item::プリミティブ描画項目エラー;
use blitz_engine::チャンク座標;

#[derive(Debug, thiserror::Error)]
pub(crate) enum 描画入力エラー {
    #[error("描画対象の所有チャンク(x={}, z={})が束のチャンク座標(x={}, z={})と一致しない", .0.x(), .0.z(), .1.x(), .1.z())]
    所有チャンク不一致(チャンク座標, チャンク座標),
    #[error("原点でない束の基準原点を導出するチャンク一辺が無い: x={}, z={}", .0.x(), .0.z())]
    チャンク一辺なし(チャンク座標),
    #[error(transparent)]
    プリミティブ描画項目の組み立て(#[from] プリミティブ描画項目エラー),
}
