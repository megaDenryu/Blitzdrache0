//! 束の描画入力を組み立てるときの失敗型。所有チャンクの照合と材質の解決という、この層だけが持つ条件をここが所有する。
//! 起動全体の失敗型へ直接足さないのは、層ごとの語彙を1つの列挙へ集めると、どの層が何を拒むのかが読めなくなるためである。

use blitz_engine::チャンク座標;

#[derive(Debug, thiserror::Error)]
pub(crate) enum 描画入力エラー {
    #[error("描画対象の所有チャンク(x={}, z={})が束のチャンク座標(x={}, z={})と一致しない", .0.x(), .0.z(), .1.x(), .1.z())]
    所有チャンク不一致(チャンク座標, チャンク座標),
    #[error("1つの描画対象が{スロット種類数}種類の材質スロットを参照している。プリミティブ別の材質描画は未対応である")]
    プリミティブ別材質描画未対応 { スロット種類数: usize },
    #[error("描画対象のプリミティブが参照する材質スロットID {番号}が材質集合に無い")]
    材質スロット未定義 { 番号: u32 },
}
