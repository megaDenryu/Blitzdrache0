//! 描画対象の形状から可視判定と段選択の材料を作る工程。受け取るのは形状と基準原点からの相対の静的変換と束の中での添字、
//! 返すのはインスタンス群のときだけ値を持つ登録である。通常メッシュと地形は個体が1体のため可視判定の対象にしない。
//! 変換を渡すのは、コンパイラが焼いた境界が群のローカル空間にあり、描画と同じ座標で判定するにはこの変換を通す必要があるためである。
//! 個体別の段の記憶をここで確保するのは、束の読込時に一度だけ個体数ぶんを取り、毎フレームは書き換えだけを行うためである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」「個体別LOD」

use blitz_engine::{個体別段状態, 可視判定エラー, 描画形状, 群可視材料};
use blitz_math::{ローカル, ワールド, 変換, 大域ワールド位置};
use blitz_render::レンダラーエラー;

use crate::app::visibility::群可視材料の登録;
use crate::error::起動エラー;

pub(super) fn 群可視材料の登録を作る(
    形状: &描画形状,
    対象添字: usize,
    大域の基準原点: 大域ワールド位置,
    ローカルからワールド: 変換<ローカル, ワールド>,
) -> Result<Option<群可視材料の登録>, 起動エラー> {
    let 描画形状::インスタンス群(群) = 形状 else {
        return Ok(None);
    };
    let 材料 = 群可視材料::群から生成する(群, ローカルからワールド).map_err(描画側のエラーへ写す)?;
    let 段状態 = 個体別段状態::生成する(群.個体数(), 群.原型().最粗段());
    Ok(Some(群可視材料の登録::生成する(対象添字, 大域の基準原点, 材料, 段状態)))
}

/// 可視判定が個体数の上限で拒む条件は、レンダラーが同じ群の個体変換列で拒む条件と同一である。
/// 同じ破れを2つの型で表すと呼び出し元がどちらを見ればよいか決められないため、描画側の型付きエラーへ写す。
fn 描画側のエラーへ写す(誤り: 可視判定エラー) -> レンダラーエラー {
    match 誤り {
        可視判定エラー::個体数過大 { 個体数 } => レンダラーエラー::個体数過大(個体数),
        // 影の視距離を検証するのは起動指定を読む地点だけであり、群の材料の組み立ては上限を1度も読まない。
        可視判定エラー::影の視距離不正 => panic!("群の材料の組み立てが影の視距離を拒んだ: この経路は上限を読まない"),
    }
}
