//! ディスクリプタへ束ねる代表材質を、その描画対象のプリミティブ描画項目から選ぶ工程。受け取るのはその対象のプリミティブ描画項目と材質集合と束の中での添字、返すのは1つの材質である。
//!
//! 1つしか選べないのは、材質ごとのディスクリプタ束縛がマルチマテリアルの段Cで入るためである。プリミティブ描画項目が持つプリミティブと材質の対応はこの選択と無関係に正しく、
//! 段Cが束縛を差し替えた時点でこの工程は要らなくなる。
//! 先頭のプリミティブ描画項目が結ぶ材質を選ぶのは、それが最詳細段の先頭プリミティブを塗る材質だからである。材質集合の最小スロットを選ぶ実装では、
//! 未使用スロットを許す契約のもとでどのプリミティブも塗らない材質を選びうる。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「段階導入」

use blitz_engine::primitive_draw_item::プリミティブ描画項目;
use blitz_engine::{マテリアルデータ, 材質集合};

use super::error::描画入力エラー;

pub(super) fn 代表材質を選ぶ<'材質>(
    対象のプリミティブ描画項目: &[プリミティブ描画項目],
    材質集合: &'材質 材質集合,
    描画対象添字: usize,
) -> Result<&'材質 マテリアルデータ, 描画入力エラー> {
    // 組み立て工程がプリミティブ不在と未定義スロットを先に拒むため、この2つの`None`へは到達しない。
    // 2つの工程の不変条件を1つの型で結べないため、到達不能を主張せず型付きエラーで返す。
    let 誤り = || 描画入力エラー::代表材質不在 { 描画対象添字 };
    let 先頭 = 対象のプリミティブ描画項目.first().ok_or_else(誤り)?;
    材質集合.材質を参照する(先頭.材質束縛().材質スロット()).ok_or_else(誤り)
}
