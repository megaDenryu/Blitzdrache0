//! 縮小段の格納バイト数の算術が、実行時形式のCPU正本(blitz_engine)とレンダラーの受け取り(blitz_render)で
//! 同じ値を出すことの突き合わせ。クレートの依存はblitz_engineからblitz_renderへの一方向であり、
//! レンダラーが正本を呼べないため同じ規則を両方が持つ。その一致の破れをここが機械で検出する。
//!
//! この検査をコンポジションルートへ置くのは、両方のクレートへ依存するのがここだけだからである。
//! 破れたときに現れるのは「焼いた段の長さがレンダラーの受け取りで拒まれる」という遠い場所の失敗であり、
//! 段の寸法によっては特定の1件でしか出ないため、格子で総当たりする。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`「段割りと各段の完了条件」の段3

#![allow(clippy::unwrap_used)]

use blitz_engine::texture_storage::テクスチャ格納形式 as 正本の格納形式;
use blitz_render::テクスチャ格納形式 as レンダラーの格納形式;

/// 突き合わせる寸法。ブロックの一辺4の倍数・その前後・1と2の極小・大きな2の冪・4の倍数でない大きな値を含める。
/// 4の倍数でない寸法を厚く採るのは、ブロック格子の切り上げが両側で同じ向きに丸められることがこの算術の要だからである。
const 突き合わせる寸法一覧: [u32; 16] = [1, 2, 3, 4, 5, 6, 7, 8, 9, 15, 16, 17, 63, 255, 511, 2048];

#[test]
fn 正本とレンダラーの縮小段の格納バイト数が格子の全点で一致する() {
    for 幅 in 突き合わせる寸法一覧 {
        for 高さ in 突き合わせる寸法一覧 {
            格子の1点で正本とレンダラーを突き合わせる(正本の格納形式::RGBA8, レンダラーの格納形式::RGBA8, 幅, 高さ);
            格子の1点で正本とレンダラーを突き合わせる(正本の格納形式::BC1, レンダラーの格納形式::BC1, 幅, 高さ);
        }
    }
}

#[test]
fn 零の寸法は正本が拒む() {
    // 正本が零の寸法を型付きエラーで拒むため、レンダラー側の値と突き合わせる相手が存在しない。
    // レンダラーの側は零の寸法を`テクスチャ素材`の生成が先に拒むため、この算術へ零が届かない。
    assert!(正本の格納形式::BC1.縮小段の格納バイト数を求める(0, 4).is_err());
    assert!(正本の格納形式::RGBA8.縮小段の格納バイト数を求める(4, 0).is_err());
}

fn 格子の1点で正本とレンダラーを突き合わせる(
    正本: 正本の格納形式, レンダラー: レンダラーの格納形式, 幅: u32, 高さ: u32
) {
    let 正本の値 = u128::from(正本.縮小段の格納バイト数を求める(幅, 高さ).unwrap());
    let レンダラーの値 = レンダラー.縮小段の格納バイト数を求める(幅, 高さ);
    assert_eq!(
        正本の値, レンダラーの値,
        "{正本:?}の{幅}×{高さ}で正本とレンダラーの格納バイト数が食い違った"
    );
}
