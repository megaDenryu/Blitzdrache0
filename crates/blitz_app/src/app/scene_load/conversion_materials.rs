//! シーンを描画入力へ写すときに、シーンの外から要る材料。担当するのは、世界ごとに決まって実行中は変わらない
//! 3つを1つの値として運ぶことである。
//!
//! 3つを別々の引数で配らないのは、写す入口が起動時・ホットリロード・チャンクの読み込みの3系統に分かれており、
//! 材料が増えるたびに全系統の署名へ同じ値を足し回ることになるためである。1つにまとめると、足す場所がこの型だけになる。
//!
//! `大域平行移動`は、チャンク座標から導出した描画の基準原点へ最後に合成する。
//! `チャンク一辺`を持たない世界は、基準原点をシーンの所有チャンクだけから導く。

use blitz_math::大域ワールド位置;

use super::surface_layer_tiles::地表の層のタイル一式;

#[derive(Clone, Copy)]
pub(crate) struct シーンを描画入力へ写す材料<'借用> {
    大域平行移動: 大域ワールド位置,                   // `--global-offset`が世界全体へ加える平行移動
    チャンク一辺: Option<blitz_engine::チャンク一辺>, // 世界がチャンクを持つときの一辺
    地表の層のタイル: &'借用 地表の層のタイル一式,
}

impl<'借用> シーンを描画入力へ写す材料<'借用> {
    pub(crate) const fn 生成する(
        大域平行移動: 大域ワールド位置,
        チャンク一辺: Option<blitz_engine::チャンク一辺>,
        地表の層のタイル: &'借用 地表の層のタイル一式,
    ) -> Self {
        Self {
            大域平行移動,
            チャンク一辺,
            地表の層のタイル,
        }
    }

    pub(super) const fn 大域平行移動(self) -> 大域ワールド位置 {
        self.大域平行移動
    }

    pub(super) const fn チャンク一辺(self) -> Option<blitz_engine::チャンク一辺> {
        self.チャンク一辺
    }

    pub(super) const fn 地表の層のタイル(self) -> &'借用 地表の層のタイル一式 {
        self.地表の層のタイル
    }
}
