//! 起動時にアセットカタログを構築する工程。受け取るのは実行時アセットの置き場とゲーム配線、返すのは解決済みのカタログである。
//!
//! 高さ場を据えることをカタログの構築と同じ工程に置くのは、据える材料がカタログだけであり、
//! 「ゲーム更新の1刻み目より前に据わっている」という順序をこの1箇所で守れるためである。

use blitz_engine::カタログ;

use crate::error::起動エラー;
use crate::runtime_assets::実行時アセットの置き場;

/// 置き場の版付きカタログを読み、生成物の相対パスを解決したうえで、その世界の高さ場をゲームへ据える。
pub(in crate::app) fn カタログを構築して高さ場を据える(
    置き場: &実行時アセットの置き場,
    ゲーム配線: &mut crate::game::ゲーム配線,
) -> Result<カタログ, 起動エラー> {
    let カタログ = 置き場.カタログのファイル().読み込む().map_err(起動エラー::カタログ読込失敗)?;
    let 高さ場 = ゲーム配線.カタログから高さ場を読み込む(&カタログ)?;
    ゲーム配線.高さ場を据える(高さ場);
    Ok(カタログ)
}
