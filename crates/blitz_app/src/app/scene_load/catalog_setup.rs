//! 起動時にアセットカタログを構築する工程。受け取るのはアセットルートとゲーム配線、返すのは解決済みのカタログである。
//!
//! 高さ場を据えることをカタログの構築と同じ工程に置くのは、据える材料がカタログだけであり、
//! 「ゲーム更新の1刻み目より前に据わっている」という順序をこの1箇所で守れるためである。

use std::path::Path;

use blitz_engine::{カタログ, 実行時カタログを読み込む};

use crate::error::起動エラー;

/// `アセットルート`配下の版付きカタログを読み、生成物の相対パスを解決したうえで、その世界の高さ場をゲームへ据える。
pub(in crate::app) fn カタログを構築して高さ場を据える(
    アセットルート: &Path,
    ゲーム配線: &mut crate::game::ゲーム配線,
) -> Result<カタログ, 起動エラー> {
    let パス = アセットルート.join("catalog.blitzcatalog");
    let カタログ = 実行時カタログを読み込む(&パス).map_err(起動エラー::カタログ読込失敗)?;
    ゲーム配線.カタログから高さ場を据える(&カタログ)?;
    Ok(カタログ)
}
