//! 世界に1つだけ置く地表層テクスチャ集を、層ごとのタイル素材としてレンダラーの語彙で保つ型。担当するのは、
//! 起動時に1度だけ読み込んだタイルを、チャンクの材質を変換するたびに引ける形で持つことである。
//!
//! タイルを持たない世界を`Option`でなく枝で表すのは、値の不在ではなく世界の性質だからである。地表層テクスチャ集を
//! 焼いていない世界は正当に存在し(検収の板の世界がそうである)、その世界のチャンクは地表の層の重ね合わせの材質を持たない。
//! 持たない世界でその材質が現れたら、焼く側と読む側の食い違いであるため型付きの失敗にする。
//!
//! 層のタイルをチャンクのシーンへ入れないのは、同じ絵がチャンクの数だけ実行時形式へ入るためである
//! (参照: `_doc/設計/マルチマテリアルと材質境界.md`「地表の層の重ね合わせ」)。

use blitz_engine::surface_layer_textures::{地表層の数, 地表層テクスチャ集の読み口};
use blitz_render::{テクスチャ用途, テクスチャ素材};

use super::convert;
use crate::error::起動エラー;

pub(crate) enum 地表の層のタイル一式 {
    /// 地表層テクスチャ集をカタログに持たない世界。地表の層の重ね合わせの材質を1つも持たない。
    タイルを持たない世界,
    タイルを持つ世界([テクスチャ素材; 地表層の数]),
}

impl 地表の層のタイル一式 {
    /// 世界に1つだけ置く地表層テクスチャ集をカタログから読み、層ごとのタイル素材へ写す。
    /// 集を持たない世界は「タイルを持たない世界」になり、失敗ではない。
    pub(in crate::app) fn カタログから読み込む(カタログ: &blitz_engine::カタログ) -> Result<Self, 起動エラー> {
        Self::読み口から作る(&地表層テクスチャ集の読み口::カタログから読み込む(カタログ)?)
    }

    fn 読み口から作る(読み口: &地表層テクスチャ集の読み口) -> Result<Self, 起動エラー> {
        let 地表層テクスチャ集の読み口::テクスチャ集を持つ世界(集) = 読み口 else {
            return Ok(Self::タイルを持たない世界);
        };
        let mut 層ごとのタイル = Vec::with_capacity(地表層の数);
        for 層番号 in 0..地表層の数 {
            層ごとのタイル.push(convert::格納済みテクスチャを変換する(
                集.層のタイル(層番号).ベースカラー(),
                テクスチャ用途::色,
            )?);
        }
        let 層ごとのタイル = 層ごとのタイル
            .try_into()
            .unwrap_or_else(|_| panic!("地表層テクスチャ集が層の数ぶんのタイルを返すという不変条件に違反した"));
        Ok(Self::タイルを持つ世界(層ごとのタイル))
    }

    /// 地表の層の重ね合わせの材質を組むときに引く。持たない世界での要求は、焼く側と読む側の食い違いであるため型付きで落とす。
    pub(super) fn 層ごとのタイル(&self) -> Result<[テクスチャ素材; 地表層の数], 起動エラー> {
        match self {
            Self::タイルを持たない世界 => Err(起動エラー::地表層テクスチャ集を持たない世界の地表材質),
            Self::タイルを持つ世界(タイル) => Ok(タイル.clone()),
        }
    }
}
