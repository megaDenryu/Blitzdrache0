//! カタログに世界級の遠景があるときだけ読み、永続束の入力へ変換する。

use blitz_engine::{アセットID, カタログ, シーンデータ, 実行時シーンのファイル};

use super::{シーンをレンダラー入力に変換する, 束の描画入力, 起動時シーンの所有チャンク};
use crate::error::起動エラー;

pub(in crate::app) fn 遠景を読み込んで変換する(
    カタログ: &カタログ,
    材料: super::シーンを描画入力へ写す材料<'_>,
) -> Result<Option<(シーンデータ, 束の描画入力)>, 起動エラー> {
    let id = アセットID::生成する(blitz_engine::height_field::世界の遠景地形の安定IDの綴り)?;
    let Some(ファイル) = 実行時シーンのファイル::カタログの安定idから作る(カタログ, &id) else {
        return Ok(None);
    };
    let シーン = ファイル.読み込む().map_err(起動エラー::シーン読込失敗)?;
    let 入力 =
        シーンをレンダラー入力に変換する(&シーン, crate::cli::描画対象の並べ方::そのまま読む(), 起動時シーンの所有チャンク, 材料)?;
    Ok(Some((シーン, 入力)))
}
