//! 植生の検収シーンのライト方針。担当するのは、この接頭辞を持つシーン群の影の範囲と、床を持つシーンの方向光の向きである。
//!
//! 既定の影は世界原点を中心とした半幅4メートルの範囲しか覆わず、チャンク中央へ敷いた群には影が1つも落ちない。
//! シャドウパスが距離区分ごとのライト視錐台で個体を絞るようになったため、この範囲のままでは検収シーンの群が1体も
//! シャドウパスへ乗らず、両パスの計数を突き合わせる判定が成立しない。そこで影の注視点と範囲をチャンク中央へ移す。
//! 床を持つ3シーンはさらに方向光をほぼ水平の-X向きにする。既定の向きでは影が個体の足元へしか伸びず、
//! 画面外の個体が画面内へ影を落とす配置も、1体の影が床を長く横切る配置も作れない。
//! 参照: `crates/blitz_asset_compiler/src/vegetation/cull_placement.rs`と
//! `crates/blitz_asset_compiler/src/vegetation/single_scene.rs`が同じ前提で配置を決める。

use crate::cli::植生の検収世界の種別;
use blitz_math::{メートル, 大域メートル, 大域ワールド位置};
use blitz_render::{
    ライティング入力, ライティング入力エラー, 光強度, 光色, 局所光源列, 影の落ち方, 影入力, 影正射影範囲, 方向光入力, 点光源の可視性, 点光源入力,
    環境光係数,
};

/// 影の正射影が見る範囲の中心。群と床を敷いたチャンクの中央である。
const 検収の影注視点メートル: f64 = 50.0;
/// 影の正射影の半幅。画面外の個体(X=150)と画面内の床の両方を1つの範囲へ収める。
const 検収の影半幅: f32 = 120.0;
const 検収の影光源距離: f32 = 200.0;
const 検収の影遠クリップ: f32 = 400.0;

pub(super) fn 方針を作る(
    種別: 植生の検収世界の種別, 有効: bool, 大域ずらし量: 大域ワールド位置
) -> ライティング入力 {
    let 影 = 影を作る(大域ずらし量);
    if 種別 == 植生の検収世界の種別::床を持たない {
        return blitz_engine::既定ライティングを作る(有効, 大域ずらし量).影を差し替える(影);
    }
    let 白 = 確定値(光色::生成する(1.0, 1.0, 1.0));
    // Yを小さく取ると影が長く伸びる。高さ36メートルの個体の影の先端がチャンク中央の床へ届く比率である。
    let 方向光 = 確定値(方向光入力::生成する(-1.0, -0.4, 0.0, 白, 確定値(光強度::生成する(3.0))));
    let 点光源位置 = 大域位置を作る(2.0, 2.0, 2.0).平行移動する(大域ずらし量);
    // 影響半径は既定ライティングと同じ値を借りる。この検収シーンの点光源は既定と同じ位置と強度であり、
    // 半径だけを別に決めると、絵が動いたときにどちらの値が効いたのかを追えなくなる。
    let 点光源 = 確定値(点光源入力::生成する(
        点光源位置,
        白,
        確定値(光強度::生成する(10.0)),
        blitz_engine::既定の影響半径を作る(),
        点光源の可視性::影なし,
    ));
    let 局所光源列 = 確定値(局所光源列::生成する(&[点光源]));
    ライティング入力::生成する(方向光, 局所光源列, 確定値(環境光係数::生成する(0.03)), 影, 影の落ち方::落とす, 有効)
}

fn 影を作る(大域ずらし量: 大域ワールド位置) -> 影入力 {
    let 影注視点 = 大域位置を作る(検収の影注視点メートル, 0.0, 検収の影注視点メートル).平行移動する(大域ずらし量);
    let 範囲 = 確定値(影正射影範囲::生成する(
        メートル::生成する(検収の影半幅),
        メートル::生成する(検収の影半幅),
        メートル::生成する(0.1),
        メートル::生成する(検収の影遠クリップ),
    ));
    確定値(影入力::生成する(影注視点, メートル::生成する(検収の影光源距離), 範囲))
}

fn 大域位置を作る(x: f64, y: f64, z: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(x), 大域メートル::生成する(y), 大域メートル::生成する(z))
}

fn 確定値<T>(結果: Result<T, ライティング入力エラー>) -> T {
    結果.unwrap_or_else(|誤り| panic!("植生の検収シーンのライト方針の定数が不正だった: {誤り}"))
}
