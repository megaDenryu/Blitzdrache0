//! 屋内の多光源の検収世界のライト方針。担当するのは「屋外の明るさをどこまで下げるか」と影の範囲であり、
//! 小屋の中へ吊る灯の並びは`lamp_row`が持つ。
//!
//! 方向光の強度を0.15に落とすのは、この世界のシーン名が`terrain`で始まらず、時刻から導いた値の上書きを受けないためである。
//! 既定の3.0のままだと戸口から差し込む方向光と地面の照り返しが屋内の明るさを支配し、点光源を0件にしても屋内が暗くならない。
//! 0にしないのは、小屋の外形が絵に出ないと屋内をどこから見ているのかが読めなくなるためである。
//!
//! 注意: この段の点光源は影を持たない。壁は光を遮らないため、屋内の灯は壁を抜けて外側の面も照らす。
//! 遮るのは点光源の影を入れる第5段階であり、この世界はその段の素材でもある
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「段割りと各段の完了条件」)。

mod lamp_row;

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};
use blitz_render::clustered_lighting::クラスタ多光源入力エラー;
use blitz_render::{
    ライティング入力, ライティング入力エラー, 光強度, 光色, 局所光源列, 影の落ち方, 影入力, 影正射影範囲, 方向光入力, 環境光係数
};

use crate::cli::局所光の件数の起動指定;

/// この世界のシーンを指す安定ID。生成側(`crates/blitz_asset_compiler/examples/generate_source_assets/stone_hut_world.rs`)と同じ綴りである。
pub(crate) const シーン識別子: &str = "prop_stone_hut_interior";

/// 小屋を据えた位置。宣言側(`crates/blitz_asset_compiler/examples/compile_assets/world/stone_hut_declaration.rs`)と同じ値である。
const 小屋の中心メートル: f64 = 50.0;

/// 屋外を残す弱い方向光の強度。
const 方向光の強度: f32 = 0.15;

/// 影の正射影が見る範囲。小屋1棟とその周りの地面を覆う。
const 影の半幅: f32 = 12.0;
const 影光源距離: f32 = 40.0;
const 影遠クリップ: f32 = 90.0;

pub(super) fn 方針を作る(
    有効: bool, 大域ずらし量: 大域ワールド位置, 件数: 局所光の件数の起動指定
) -> ライティング入力 {
    let 白 = 確定値(光色::生成する(1.0, 1.0, 1.0));
    let 方向光 = 確定値(方向光入力::生成する(-0.4, -1.0, 0.6, 白, 確定値(光強度::生成する(方向光の強度))));
    let 灯一覧 = lamp_row::灯の一覧を作る(灯数を決める(件数), 大域ずらし量);
    let 局所光源列 = 確定値(局所光源列::生成する(&灯一覧));
    let 影 = 確定値(影入力::生成する(
        小屋の中の位置を作る(0.0, 0.0, 大域ずらし量),
        メートル::生成する(影光源距離),
        影の範囲を作る(),
    ));
    ライティング入力::生成する(方向光, 局所光源列, 確定値(環境光係数::生成する(0.02)), 影, 影の落ち方::落とす, 有効)
}

/// 宣言より多い件数を指定されても宣言の件数で頭を打つ。屋内の灯は宣言した3件で並びが閉じており、
/// 4件目の置き場所がこの世界には無いためである。
fn 灯数を決める(件数: 局所光の件数の起動指定) -> usize {
    match 件数 {
        局所光の件数の起動指定::世界の宣言に従う => lamp_row::既定の灯数(),
        局所光の件数の起動指定::件数を上書きする(件数) => 件数.min(lamp_row::既定の灯数()),
    }
}

/// 小屋の中心から横へずらし、指定の高さへ置いた位置。
fn 小屋の中の位置を作る(横のずれ: f64, 天頂: f64, 大域ずらし量: 大域ワールド位置) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(小屋の中心メートル + 横のずれ),
        大域メートル::生成する(天頂),
        大域メートル::生成する(小屋の中心メートル),
    )
    .平行移動する(大域ずらし量)
}

fn 影の範囲を作る() -> 影正射影範囲 {
    確定値(影正射影範囲::生成する(
        メートル::生成する(影の半幅),
        メートル::生成する(影の半幅),
        メートル::生成する(0.1),
        メートル::生成する(影遠クリップ),
    ))
}

fn 確定値<T>(結果: Result<T, ライティング入力エラー>) -> T {
    結果.unwrap_or_else(|誤り| panic!("屋内の多光源の検収世界のライト方針の定数が不正だった: {誤り}"))
}

fn クラスタ多光源の確定値<T>(結果: Result<T, クラスタ多光源入力エラー>) -> T {
    結果.unwrap_or_else(|誤り| panic!("屋内の多光源の検収世界の影響半径が不正だった: {誤り}"))
}
