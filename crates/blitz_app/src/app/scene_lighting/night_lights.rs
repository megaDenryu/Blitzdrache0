//! 夜の多光源の検収世界のライト方針。担当するのは「この世界が何件の点光源をどこへ置くか」と、
//! 方向光・環境光・影の範囲をこの世界の広さへ合わせることだけであり、時刻の配線は知らない。
//!
//! 方向光と環境光の値をここで決めても夜の絵には現れない。シーン名が`terrain`で始まるため時刻から導いた値が
//! 上書きし、一日内秒75600の夜では方向光の強度がほぼ0になるからである。それでも既定と同じ値を宣言するのは、
//! 昼の時刻で同じ世界を撮ったときに他の地形の世界と同じ明るさになり、灯の寄与だけを差として読めるようにするためである。
//!
//! 影の正射影を灯の並びへ合わせるのは、既定の半幅4メートルが世界原点を見ており、この世界の地面
//! (チャンク中央の一辺52.5メートルの並び)を1メートルも覆わないためである。
//! 参照: `_doc/設計/クラスタ多光源と点光源の影.md`「検収戦略(判断i)」

mod lamp_field;
#[cfg(test)]
mod lamp_field_tests;

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};
use blitz_render::clustered_lighting::クラスタ多光源入力エラー;
use blitz_render::{
    ライティング入力, ライティング入力エラー, 光強度, 光色, 局所光源列, 影の落ち方, 影入力, 影正射影範囲, 方向光入力, 環境光係数
};

use crate::cli::局所光の件数の起動指定;

/// この世界のシーンを指す安定ID。生成側(`crates/blitz_asset_compiler/examples/generate_source_assets/night_lights_world.rs`)と同じ綴りである。
pub(crate) const シーン識別子: &str = "terrain_night_lights";

/// 影の正射影が見る範囲の中心と半幅。灯の並び(中心から26.25メートル)と、その外の下りの手前までを1つの範囲へ収める。
const 影注視点メートル: f64 = 50.0;
const 影の半幅: f32 = 40.0;
const 影光源距離: f32 = 120.0;
const 影遠クリップ: f32 = 260.0;

pub(super) fn 方針を作る(
    有効: bool, 大域ずらし量: 大域ワールド位置, 件数: 局所光の件数の起動指定
) -> ライティング入力 {
    let 白 = 確定値(光色::生成する(1.0, 1.0, 1.0));
    let 方向光 = 確定値(方向光入力::生成する(-0.4, -1.0, -0.6, 白, 確定値(光強度::生成する(3.0))));
    let 灯一覧 = lamp_field::灯の一覧を作る(灯数を決める(件数), 大域ずらし量);
    let 局所光源列 = 確定値(局所光源列::生成する(&灯一覧));
    let 影 = 確定値(影入力::生成する(
        影注視点を作る(大域ずらし量),
        メートル::生成する(影光源距離),
        影の範囲を作る(),
    ));
    ライティング入力::生成する(方向光, 局所光源列, 確定値(環境光係数::生成する(0.03)), 影, 影の落ち方::落とす, 有効)
}

fn 灯数を決める(件数: 局所光の件数の起動指定) -> usize {
    match 件数 {
        局所光の件数の起動指定::世界の宣言に従う => lamp_field::既定の灯数(),
        局所光の件数の起動指定::件数を上書きする(件数) => 件数,
    }
}

fn 影の範囲を作る() -> 影正射影範囲 {
    確定値(影正射影範囲::生成する(
        メートル::生成する(影の半幅),
        メートル::生成する(影の半幅),
        メートル::生成する(0.1),
        メートル::生成する(影遠クリップ),
    ))
}

fn 影注視点を作る(大域ずらし量: 大域ワールド位置) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(影注視点メートル),
        大域メートル::生成する(0.0),
        大域メートル::生成する(影注視点メートル),
    )
    .平行移動する(大域ずらし量)
}

fn 確定値<T>(結果: Result<T, ライティング入力エラー>) -> T {
    結果.unwrap_or_else(|誤り| panic!("夜の多光源の検収世界のライト方針の定数が不正だった: {誤り}"))
}

fn クラスタ多光源の確定値<T>(結果: Result<T, クラスタ多光源入力エラー>) -> T {
    結果.unwrap_or_else(|誤り| panic!("夜の多光源の検収世界の影響半径が不正だった: {誤り}"))
}
