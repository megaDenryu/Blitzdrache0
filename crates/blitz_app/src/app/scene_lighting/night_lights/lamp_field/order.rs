//! 正方格子の灯を中心から近い順に並べる規則。受け取るのは置く件数、返すのは格子の添字の並びである。
//! 触れる状態を持たず、呼び出し元は格子の座標の作り方を知らずに呼べる。
//!
//! 中心から近い順にするのは、件数を減らしたときに中心から遠い灯から消え、どの件数でも構図の中央に灯が
//! 残るようにするためである。端から順に消すと、件数が少ない絵だけ灯が画面の隅へ寄り、明るさの比較が
//! 構図の違いに埋もれる。影を落とす灯を選ぶ順も同じ並びを読む。

use super::一辺の灯数;

/// 格子の添字を中心から近い順に並べ、先頭から指定の件数だけ返す。同じ環の中の順は添字の昇順である
/// (安定な並べ替えを使うため、環番号が等しい要素の相対順は変わらない)。
pub(super) fn 中心から近い順の格子添字(灯数: usize) -> Vec<u16> {
    let mut 添字一覧: Vec<u16> = (0..一辺の灯数 * 一辺の灯数).collect();
    添字一覧.sort_by_key(|&添字| 中心からの環番号(添字));
    添字一覧.truncate(灯数);
    添字一覧
}

pub(super) fn 列と行(格子添字: u16) -> (u16, u16) {
    (格子添字 % 一辺の灯数, 格子添字 / 一辺の灯数)
}

/// 中心からの環の番号。格子の中心は列と行のあいだにあるため、2倍した座標で測って整数のまま比べる。
fn 中心からの環番号(格子添字: u16) -> u16 {
    let (列, 行) = 列と行(格子添字);
    中心からの差(列).max(中心からの差(行))
}

fn 中心からの差(位置: u16) -> u16 {
    (2 * 位置).abs_diff(一辺の灯数 - 1)
}
