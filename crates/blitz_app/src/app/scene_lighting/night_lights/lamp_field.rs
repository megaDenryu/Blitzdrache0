//! 夜の多光源の検収世界へ置く街灯の並び。受け取るのは置く件数と世界全体の平行移動、返すのは点光源入力の列である。
//! 触れる状態を持たず、担うのは並びの決め方(場所・色・強度・影響半径)と、件数を減らしたときにどれから消えるかの順である。
//!
//! 8かける8の正方格子へ置くのは、局所光源列の上限が64件であり、全部置いた形が上限そのものになるためである。
//! 間隔7.5メートル・高さ4.0メートル・影響半径10.0メートルの組は、隣り合う灯の明るさの輪が縁で少しだけ重なる値である。
//! 重なりを作るのは、クラスタ格子の同じセルへ2件以上の光が割り当てられる場面をこの世界で成立させるためである。
//! 重なりが1つも無いと、セルあたりの割り当て件数が常に1以下になり、選別が絞る前と後を数で比べられない。
//!
//! 件数を減らすときに中心から遠い灯から消すのは、どの件数でも構図の中央に灯があるようにするためである。
//! 端から順に消すと、件数が少ない絵だけ灯が画面の隅へ寄り、明るさの比較が構図の違いに埋もれる。
//!
//! 色を市松に置くのは、どの灯がどの地面を照らしているかを絵で見分けるためである。全部を同じ色にすると、
//! 隣り合う灯の輪が重なった場所と1件だけが届く場所を色で区別できない。

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};
use blitz_render::clustered_lighting::影響半径;
use blitz_render::{光強度, 光色, 点光源入力};

use super::{クラスタ多光源の確定値, 確定値};

/// 正方格子の一辺の灯の数。積が局所光源列の上限件数(64)と一致する。
const 一辺の灯数: u16 = 8;
/// 隣り合う灯の間隔。
const 灯の間隔メートル: f32 = 7.5;
/// 地面から灯までの高さ。
const 灯の高さメートル: f32 = 4.0;
/// 灯が届く範囲。間隔7.5メートルに対して10.0メートルであるから、輪は隣とだけ重なり、1つ飛ばした先へは届かない。
const 灯の影響半径メートル: f32 = 10.0;
/// 灯の明るさ。高さ4.0メートルの真下で逆二乗の値が3.75になり、地面が飽和せずに読み取れる明るさになる。
const 灯の強度: f32 = 60.0;
/// 並びの中心。チャンクの大域原点はX最小・Z最小の角にあるため、一辺100メートルの半分だけ内側である。
const 並びの中心メートル: f32 = 50.0;

/// 暖かい側の灯の色。
const 暖色: [f32; 3] = [1.0, 0.78, 0.5];
/// 冷たい側の灯の色。
const 寒色: [f32; 3] = [0.55, 0.72, 1.0];

/// 世界がこの指定を受けなかったときに置く件数。上限まで置いた形を既定にする。
pub(super) fn 既定の灯数() -> usize {
    usize::from(一辺の灯数) * usize::from(一辺の灯数)
}

pub(super) fn 灯の一覧を作る(灯数: usize, 大域ずらし量: 大域ワールド位置) -> Vec<点光源入力> {
    中心から近い順の格子添字(灯数)
        .into_iter()
        .map(|格子添字| 灯を1つ作る(格子添字, 大域ずらし量))
        .collect()
}

/// 格子の添字を中心から近い順に並べ、先頭から指定の件数だけ返す。同じ環の中の順は添字の昇順である
/// (安定な並べ替えを使うため、環番号が等しい要素の相対順は変わらない)。
fn 中心から近い順の格子添字(灯数: usize) -> Vec<u16> {
    let mut 添字一覧: Vec<u16> = (0..一辺の灯数 * 一辺の灯数).collect();
    添字一覧.sort_by_key(|&添字| 中心からの環番号(添字));
    添字一覧.truncate(灯数);
    添字一覧
}

/// 中心からの環の番号。格子の中心は列と行のあいだにあるため、2倍した座標で測って整数のまま比べる。
fn 中心からの環番号(格子添字: u16) -> u16 {
    let (列, 行) = 列と行(格子添字);
    中心からの差(列).max(中心からの差(行))
}

fn 中心からの差(位置: u16) -> u16 {
    (2 * 位置).abs_diff(一辺の灯数 - 1)
}

fn 列と行(格子添字: u16) -> (u16, u16) {
    (格子添字 % 一辺の灯数, 格子添字 / 一辺の灯数)
}

fn 灯を1つ作る(格子添字: u16, 大域ずらし量: 大域ワールド位置) -> 点光源入力 {
    let (列, 行) = 列と行(格子添字);
    let 位置 = 大域位置を作る(格子の座標メートル(列), 灯の高さメートル, 格子の座標メートル(行)).平行移動する(大域ずらし量);
    let 色 = if (列 + 行) % 2 == 0 { 暖色 } else { 寒色 };
    確定値(点光源入力::生成する(
        位置,
        確定値(光色::生成する(色[0], 色[1], 色[2])),
        確定値(光強度::生成する(灯の強度)),
        クラスタ多光源の確定値(影響半径::生成する(メートル::生成する(灯の影響半径メートル))),
    ))
}

/// 1つの軸について、格子の添字から並びの中心を基準にした位置を返す。
fn 格子の座標メートル(位置: u16) -> f32 {
    let 中心の添字 = f32::from(一辺の灯数 - 1) * 0.5;
    並びの中心メートル + (f32::from(位置) - 中心の添字) * 灯の間隔メートル
}

fn 大域位置を作る(x: f32, y: f32, z: f32) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(f64::from(x)),
        大域メートル::生成する(f64::from(y)),
        大域メートル::生成する(f64::from(z)),
    )
}
