//! 街灯の並びの検査。確かめるのは3つである。件数がそのまま灯の数になること、件数を減らした並びが
//! 上限の並びの先頭からの部分列であること、そして先に残る灯ほど並びの中心に近いことである。
//!
//! 部分列であることを課すのは、件数を振った実験の条件が入れ子になっていなければならないためである。
//! 件数を減らしたときに別の場所へ灯が移ると、件数の違いと場所の違いが計測値の上で混ざる。
//!
//! 中心に近い順であることを課すのは、どの件数でも構図の中央に灯があるようにするためである。

#![allow(clippy::unwrap_used)]

use blitz_math::{大域メートル, 大域ワールド位置};

use super::lamp_field::{既定の灯数, 灯の一覧を作る};

fn 原点() -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(0.0), 大域メートル::生成する(0.0))
}

fn 水平位置の一覧(灯数: usize) -> Vec<(f64, f64)> {
    灯の一覧を作る(灯数, 原点())
        .into_iter()
        .map(|灯| (灯.位置().x().値(), 灯.位置().z().値()))
        .collect()
}

#[test]
fn 件数がそのまま灯の数になる() {
    for 灯数 in [0_usize, 1, 8, 32, 既定の灯数()] {
        assert_eq!(水平位置の一覧(灯数).len(), 灯数);
    }
}

#[test]
fn 件数を減らした並びは上限の並びの先頭からの部分列である() {
    let 上限の並び = 水平位置の一覧(既定の灯数());
    for 灯数 in [1_usize, 8, 32] {
        assert_eq!(水平位置の一覧(灯数), 上限の並び[..灯数], "{灯数}件の並びが先頭から食い違った");
    }
}

/// 並びの中心は(50, 50)である。先に残る灯ほど中心に近いことを、中心からの距離が単調に増えないことで見る。
#[test]
fn 先に残る灯ほど並びの中心に近い() {
    let 中心 = 50.0;
    let 距離一覧: Vec<f64> = 水平位置の一覧(既定の灯数())
        .into_iter()
        .map(|(x, z)| (x - 中心).abs().max((z - 中心).abs()))
        .collect();
    for 対 in 距離一覧.windows(2) {
        assert!(対[0] <= 対[1] + 1.0e-6, "中心から遠い灯が先に来た: {対:?}");
    }
}

#[test]
fn 同じ件数からは同じ並びが出る() {
    assert_eq!(水平位置の一覧(32), 水平位置の一覧(32));
}
