//! 小屋の中へ吊る灯の並び。受け取るのは置く件数と世界全体の平行移動、返すのは点光源入力の列である。
//! 触れる状態を持たず、担うのは並びの決め方(場所・色・強度・影響半径)と、件数を減らしたときにどれから消えるかの順である。
//!
//! 3件を横1列へ置くのは、小屋の内法が幅3.0・奥行2.0メートルであり、1メートル間隔の3件が壁に触れずに収まるためである。
//! 中心の1件を先頭に置くのは、件数を1件へ減らした絵でも屋内の中央が照らされているようにするためである。
//! 端から消す順にすると、1件だけの絵で光が壁際へ寄り、屋内の明るさの比較が位置の違いに埋もれる。
//!
//! 色を交互にするのは、どの灯がどの面を照らしているかを絵で見分けるためである。
//!
//! 影を落とすのは宣言の順に先頭から数えた件数までである。中心の1件を先頭に置いてあるため、影を1件だけにした絵でも
//! 中央の灯が壁を遮る形になる。世界の既定を1件にするのは、壁の継ぎ目の漏光が中央の灯1件で判定できるためである。

use blitz_math::{メートル, 大域ワールド位置};
use blitz_render::clustered_lighting::影響半径;
use blitz_render::{光強度, 光色, 点光源の可視性, 点光源入力};

use crate::cli::影を落とす灯の件数の起動指定;

use super::{クラスタ多光源の確定値, 小屋の中の位置を作る, 確定値};

/// 屋内の灯の高さ。小屋の内法の高さがおよそ2.66メートルであるため、天井から少し下がった位置になる。
const 灯の高さメートル: f64 = 2.0;

/// 灯を並べる横方向の間隔。
const 灯の間隔メートル: f64 = 1.0;

/// 灯が届く範囲。小屋の内法(幅3.0・奥行2.0・高さ2.66メートル)の隅まで届く値である。
const 灯の影響半径メートル: f32 = 4.0;

/// 灯の明るさ。高さ2.0メートルの真下で逆二乗の値が2.0になり、床が飽和せずに読み取れる明るさになる。
const 灯の強度: f32 = 8.0;

/// 灯を置く横方向のずれと色。中心を先頭に置き、件数を減らしたときに端から消えるようにする。
const 灯の並び: [(f64, [f32; 3]); 3] = [
    (0.0, [1.0, 0.82, 0.55]),
    (-灯の間隔メートル, [0.6, 0.75, 1.0]),
    (灯の間隔メートル, [1.0, 0.82, 0.55]),
];

/// 世界がこの指定を受けなかったときに置く件数。
pub(super) fn 既定の灯数() -> usize {
    灯の並び.len()
}

/// 世界がこの指定を受けなかったときに影を落とす件数。中心の1件だけである。
const 既定の影を落とす灯数: usize = 1;

pub(super) fn 灯の一覧を作る(
    灯数: usize,
    影を落とす件数: 影を落とす灯の件数の起動指定,
    大域ずらし量: 大域ワールド位置,
) -> Vec<点光源入力> {
    灯の並び
        .iter()
        .take(灯数)
        .enumerate()
        .map(|(順番, &(横のずれ, 色))| {
            確定値(点光源入力::生成する(
                小屋の中の位置を作る(横のずれ, 灯の高さメートル, 大域ずらし量),
                確定値(光色::生成する(色[0], 色[1], 色[2])),
                確定値(光強度::生成する(灯の強度)),
                クラスタ多光源の確定値(影響半径::生成する(メートル::生成する(灯の影響半径メートル))),
                可視性を決める(順番, 影を落とす件数),
            ))
        })
        .collect()
}

fn 可視性を決める(順番: usize, 影を落とす件数: 影を落とす灯の件数の起動指定) -> 点光源の可視性 {
    if 影を落とす件数.宣言の順番が影を落とすか(順番, 既定の影を落とす灯数) {
        点光源の可視性::立方体影
    } else {
        点光源の可視性::影なし
    }
}
