//! 世界ごとの多段設定。最大影距離は「その世界のどこまで影を出すか」であり、世界の広がりで決まるため、
//! 影の注視点・正射影範囲と同じくシーンごとの方針として持つ。分割の混ぜ方・重なり・キャスター余白は世界に依らない。
//!
//! 既定の300メートルは検証用地形世界(一辺100メートルのチャンクが5×5)へ合わせた値である。
//! 一辺100メートルの単一チャンクしか持たない検収世界では、300メートルの距離区分が世界の外まで覆い、
//! 「影の範囲の外に置いた個体」がすべて影の候補に入ってしまう。そこで世界の広がりに合わせて縮める。

use blitz_math::メートル;
use blitz_render::cascade::多段設定;

/// 植生の検収世界の最大影距離。影の正射影の半幅120メートルと同じ桁にそろえる。
/// この世界は群(チャンク中央)・床・画面外から影を投げる個体(X=150)・視錐台外の番兵(X=-300)を1つの構図へ収めており、
/// 影が届くべき広がりは150メートル程度である。番兵はこの距離の多段の外に留まる。
const 植生検収世界の最大影距離: f32 = 120.0;

/// 群が両方の視錐台の外にある検収世界の最大影距離。群はチャンク中央(原点から約70メートル)にあり、
/// 既定カメラは原点付近を見る。20メートルにすると群は多段の外に留まり、この世界の目的
/// (シャドウパスの入力が空になる状態を作ること)が保たれる。
const 両視錐台外の世界の最大影距離: f32 = 20.0;

/// 一辺解像度は世界の方針でなく計測の起動指定から来る。世界ごとに違えると、同じ世界を別の解像度で測った
/// 比較が世界の違いと解像度の違いを混ぜてしまうため、全世界へ同じ値を敷く。
pub(super) fn シーンの多段設定を作る(シーン名: &str, 計測: &crate::cli::シャドウ計測起動設定) -> 多段設定 {
    let 既定 = キャスター余白を反映する(多段設定::既定().解像度を差し替える(計測.一辺解像度), 計測.キャスター余白);
    let 最大影距離 = if シーン名 == super::両視錐台外の群シーン {
        両視錐台外の世界の最大影距離
    } else if シーン名.starts_with(super::植生検収シーンの接頭辞) {
        植生検収世界の最大影距離
    } else {
        return 既定;
    };
    既定
        .最大影距離を差し替える(メートル::生成する(最大影距離))
        .unwrap_or_else(|誤り| panic!("検収世界の多段設定の定数が不正だった: {誤り}"))
}

/// 起動指定の余白を多段設定へ反映する。指定が無ければ世界の既定の余白をそのまま使う。
fn キャスター余白を反映する(設定: 多段設定, 余白: Option<メートル>) -> 多段設定 {
    let Some(余白) = 余白 else { return 設定 };
    設定
        .キャスター余白を差し替える(余白)
        .unwrap_or_else(|誤り| panic!("起動指定のキャスター余白が検証を満たさない: {誤り}"))
}
