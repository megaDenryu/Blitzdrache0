//! 遠方環境の消費を機械判定する検収世界のライト方針。担当するのは「この世界の直接光をどこまで消すか」だけであり、
//! 影の多段設定も時刻の配線も知らない。
//!
//! 局所光を1件も宣言しないのは、判定が間接光だけを画素へ出すためである。方向光は時刻から導かれて世界の値を
//! 上書きするため、ここで0にしても効かない。方向光が0になるのは夜の時刻を選んだ実行だけであり
//! (`太陽光方針::昼係数に応じた強度`)、解析入力を注入する判定はその時刻で走る。
//! 強度0の点光源1件でなく件数0の列にしたのは、局所光源列が「光を持たない」を件数で表せるためである。
//! 強度0の光の寄与はどちらの形でもちょうど0であり、画素は変わらない。
//! 影の正射影を既定と同じ半幅4メートルに置くのは、板が世界原点の近くに並ぶためである。

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};
use blitz_render::{
    ライティング入力, ライティング入力エラー, 光強度, 光色, 局所光源列, 影の落ち方, 影入力, 影正射影範囲, 方向光入力, 環境光係数
};

pub(super) const シーン識別子: &str = "indirect_probe";

const 影光源距離: f32 = 10.0;
const 影の半幅: f32 = 4.0;

pub(super) fn 方針を作る(有効: bool, 大域ずらし量: 大域ワールド位置) -> ライティング入力 {
    let 白 = 確定値(光色::生成する(1.0, 1.0, 1.0));
    let 方向光 = 確定値(方向光入力::生成する(-0.4, -1.0, -0.6, 白, 確定値(光強度::生成する(3.0))));
    let 原点 = 原点を作る(大域ずらし量);
    let 局所光を持たない列 = 確定値(局所光源列::生成する(&[]));
    let 影 = 確定値(影入力::生成する(原点, メートル::生成する(影光源距離), 影の範囲を作る()));
    ライティング入力::生成する(
        方向光,
        局所光を持たない列,
        確定値(環境光係数::生成する(0.03)),
        影,
        影の落ち方::落とす,
        有効,
    )
}

fn 影の範囲を作る() -> 影正射影範囲 {
    確定値(影正射影範囲::生成する(
        メートル::生成する(影の半幅),
        メートル::生成する(影の半幅),
        メートル::生成する(0.1),
        メートル::生成する(20.0),
    ))
}

fn 原点を作る(大域ずらし量: 大域ワールド位置) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(0.0), 大域メートル::生成する(0.0)).平行移動する(大域ずらし量)
}

fn 確定値<T>(結果: Result<T, ライティング入力エラー>) -> T {
    結果.unwrap_or_else(|誤り| panic!("遠方環境の検収世界のライト方針の定数が不正だった: {誤り}"))
}
