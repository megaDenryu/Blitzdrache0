//! 大規模世界の距離区分の割り当て。受け取るものは無く、返すのは名指しの境界で分ける割り当てである。
//!
//! 4つの距離区分は世界の構造と1対1で対応する。第1区分は接地影、第2区分は一辺100メートルの1チャンク、
//! 第3区分は先読み半径8の近傍層、第4区分は遠景層を担当する。実用分割へ最大影距離10000メートルだけを渡すと
//! 境界が約1001・2019・3337メートルになり、近景の3区分をまとめて失うため、境界は計算でなく名指しで置く。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「大規模世界だけは明示境界25メートル・100メートル・1000メートル・10000メートルを使い」

use blitz_math::メートル;
use blitz_render::cascade::{明示の距離区分境界, 距離区分の割り当て};

/// 接地影の境界。既定の225メートルの実用分割が置く第1境界22.94メートルに近い距離を選び、
/// 足元の影の細かさをこの再配分で落とさない。
const 接地影の境界メートル: f32 = 25.0;
/// 1チャンクの境界。地形チャンクの一辺が100メートルであり、第2区分は自分の乗っているチャンクを覆う。
const 一チャンクの境界メートル: f32 = 100.0;
/// 先読み層の境界。先読み半径8と一辺100メートルで常駐する近傍の広がり(片側800メートル)を覆う。
const 先読み層の境界メートル: f32 = 1000.0;
/// 遠景層の最大影距離。カメラの遠クリップと同じ距離であり、第4区分が遠景メッシュ全体を受け持つ。
const 遠景層の最大影距離メートル: f32 = 10000.0;

pub(in crate::app) fn 大規模世界の距離区分の割り当てを作る() -> 距離区分の割り当て {
    let 境界 = 明示の距離区分境界::生成する([
        メートル::生成する(接地影の境界メートル),
        メートル::生成する(一チャンクの境界メートル),
        メートル::生成する(先読み層の境界メートル),
    ])
    .unwrap_or_else(|誤り| panic!("大規模世界の距離区分の境界の定数が不正だった: {誤り}"));
    距離区分の割り当て::明示の境界で分ける(境界, メートル::生成する(遠景層の最大影距離メートル))
        .unwrap_or_else(|誤り| panic!("大規模世界の距離区分の割り当ての定数が不正だった: {誤り}"))
}
