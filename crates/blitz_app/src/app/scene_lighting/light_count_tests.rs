//! 世界ごとの局所光の件数の受理範囲の検査。確かめるのは3つである。夜の世界が上限の64件まで受けること、
//! 屋内の世界が宣言した3件までしか受けないこと、そして件数の上書きを読まない世界がその指定を型付きの失敗にすることである。
//!
//! 受理範囲を世界ごとに検査するのは、上限を超えた指定を黙って縮める形が「指定が効いていない実行」を
//! 成功として通すためである。件数を振ったつもりの計測が同じ条件の繰り返しになる破れは、値からは読めない。

#![allow(clippy::unwrap_used)]

use blitz_math::{大域メートル, 大域ワールド位置};

use super::シーン初期ライティングを作る;
use crate::cli::{
    シャドウ計測起動設定, 地形の夜灯り世界の綴り, 局所光の件数の起動指定, 影を落とす灯の件数の起動指定, 石の小屋の屋内の小物世界の綴り, 起動時シーン,
};

fn 原点() -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(0.0), 大域メートル::生成する(0.0))
}

fn 件数を指定して作る(綴り: &str, 件数: 局所光の件数の起動指定) -> Result<usize, String> {
    let シーン = 起動時シーン::綴りから解析する(綴り).unwrap();
    シーン初期ライティングを作る(
        &シーン,
        true,
        原点(),
        &シャドウ計測起動設定::既定値(),
        件数,
        影を落とす灯の件数の起動指定::世界の宣言に従う,
    )
    .map(|入力| 入力.局所光源列().件数())
    .map_err(|誤り| 誤り.to_string())
}

#[test]
fn 夜の世界は0件から上限の64件までを受ける() {
    for 件数 in [0_usize, 1, 8, 32, 64] {
        let 実測 = 件数を指定して作る(地形の夜灯り世界の綴り, 局所光の件数の起動指定::件数を上書きする(件数));
        assert_eq!(実測, Ok(件数), "夜の世界が{件数}件を受けなかった");
    }
}

#[test]
fn 夜の世界の既定は上限の64件である() {
    assert_eq!(
        件数を指定して作る(地形の夜灯り世界の綴り, 局所光の件数の起動指定::世界の宣言に従う),
        Ok(64)
    );
}

#[test]
fn 屋内の世界は0件から3件までを受ける() {
    for 件数 in [0_usize, 1, 2, 3] {
        let 実測 = 件数を指定して作る(石の小屋の屋内の小物世界の綴り, 局所光の件数の起動指定::件数を上書きする(件数));
        assert_eq!(実測, Ok(件数), "屋内の世界が{件数}件を受けなかった");
    }
}

/// 4件目の置き場所がこの世界に無いため、黙って3件へ縮めず失敗させる。
#[test]
fn 屋内の世界は4件以上を型付きの失敗にする() {
    for 件数 in [4_usize, 64] {
        let 実測 = 件数を指定して作る(石の小屋の屋内の小物世界の綴り, 局所光の件数の起動指定::件数を上書きする(件数));
        assert!(実測.is_err(), "屋内の世界が{件数}件を受けてしまった");
    }
}

#[test]
fn 件数の上書きを読まない世界はその指定を型付きの失敗にする() {
    assert!(件数を指定して作る("quad", 局所光の件数の起動指定::件数を上書きする(1)).is_err());
    assert!(件数を指定して作る("quad", 局所光の件数の起動指定::世界の宣言に従う).is_ok());
}
