//! 常駐する束を据える局面。起動時の1回と、ホットリロードで起動時シーンを読み直したときの1回だけ呼ばれ、
//! 毎フレームのストリーミングの出入りとは呼び出し頻度も受け取る材料も違う。
//! 担当するのは、レンダラーへ起動時シーンと遠景を渡し、同じ束IDで2つの台帳を据え直すことである。
//! ホットリロードの回は、シーンの変換を反映準備(`resource_wiring/asset_apply/preparation.rs`)が状態を変えずに済ませており、
//! ここは変換済みの描画入力を受け取って据えるだけである。

use blitz_render::レンダラー;

use super::{シーンを描画入力へ写す材料, 地表の層のタイル一式, 描画束の台帳, 束の登録一式};
use crate::app::scene_load::束の描画入力;
use crate::error::起動エラー;

impl 描画束の台帳 {
    /// 起動時に1度だけ、レンダラーへ渡し終えた起動時シーンと遠景を台帳へ登録し、その世界の層のタイルを据える。
    /// タイルを同じ呼び出しで据えるのは、以後の束の変換がこの世代のタイルを参照するためである。
    pub(in crate::app) fn 起動時に登録する(
        &mut self, レンダラー: &mut レンダラー, 登録一式: 束の登録一式, 遠景: Option<(blitz_engine::シーンデータ, 束の描画入力)>, 地表の層のタイル: 地表の層のタイル一式
    ) -> Result<(), 起動エラー> {
        self.地表の層のタイル = 地表の層のタイル;
        self.永続束.起動時に登録する(レンダラー, &mut self.可視判定, &mut self.プリミティブ描画項目, 登録一式, 遠景)
    }

    /// 預かってある遠景を、新しい世代の写す材料で描画入力へ写し直す。台帳は書き換えない。遠景を持たない世界では無い。
    pub(in crate::app) fn 預かってある遠景を写し直す(&self, 写す材料: シーンを描画入力へ写す材料<'_>) -> Result<Option<束の描画入力>, 起動エラー> {
        self.永続束.遠景を写し直す(写す材料)
    }

    /// レンダラーのシーンを差し替えた直後に、変換済みの登録一式と遠景で2つの台帳を据え直す。
    /// レンダラーを受け取らず結果も返さないのは、遠景が起動時に登録済みであり、この経路がGPUへ触らないためである。
    pub(in crate::app) fn 起動時シーンと遠景を再登録する(&mut self, 登録一式: 束の登録一式, 遠景: Option<束の描画入力>) {
        self.永続束.登録済みの遠景のまま束を据え直す(&mut self.可視判定, &mut self.プリミティブ描画項目, 登録一式, 遠景);
    }
}
