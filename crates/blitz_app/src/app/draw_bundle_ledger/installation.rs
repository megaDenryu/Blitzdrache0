//! 常駐する束を据える局面。起動時の1回と、ホットリロードで起動時シーンを読み直したときの1回だけ呼ばれ、
//! 毎フレームのストリーミングの出入りとは呼び出し頻度も受け取る材料も違う。
//! 担当するのは、レンダラーへ起動時シーンと遠景を渡し、同じ束IDで2つの台帳を据え直すことである。

use blitz_render::レンダラー;

use super::{シーンを描画入力へ写す材料, 地表の層のタイル一式, 描画束の台帳, 束の登録一式};
use crate::app::scene_load::{シーンをレンダラー入力に変換する, 束の描画入力, 起動時シーンの所有チャンク, 起動時シーンの束ID};
use crate::error::起動エラー;

/// ホットリロードが読み直した起動時シーンを、レンダラーと台帳へ載せ直すために要る材料。
/// 5つを別々の引数で配らないのは、どれか1つを足すたびに呼び出し側の綴りが伸びるためである。
pub(in crate::app) struct 起動時シーンの差し替え材料<'借用> {
    pub(in crate::app) シーン: &'借用 blitz_engine::シーンデータ,
    pub(in crate::app) 並べ方: crate::cli::描画対象の並べ方,
    pub(in crate::app) 大域ずらし量: blitz_math::大域ワールド位置,
    pub(in crate::app) チャンク一辺: Option<blitz_engine::チャンク一辺>,
    pub(in crate::app) ゲーム配線: &'借用 crate::game::ゲーム配線,
}

impl 描画束の台帳 {
    /// 起動時に1度だけ、レンダラーへ渡し終えた起動時シーンと遠景を台帳へ登録し、その世界の層のタイルを据える。
    /// タイルを同じ呼び出しで据えるのは、以後の束の変換がこの世代のタイルを参照するためである。
    pub(in crate::app) fn 起動時に登録する(
        &mut self, レンダラー: &mut レンダラー, 登録一式: 束の登録一式, 遠景: Option<(blitz_engine::シーンデータ, 束の描画入力)>, 地表の層のタイル: 地表の層のタイル一式
    ) -> Result<(), 起動エラー> {
        self.地表の層のタイル = 地表の層のタイル;
        self.永続束.起動時に登録する(レンダラー, &mut self.可視判定, &mut self.プリミティブ描画項目, 登録一式, 遠景)
    }

    /// ホットリロードで読み直した起動時シーンをレンダラーへ差し替え、預かってある遠景ごと台帳を据え直す。
    pub(in crate::app) fn 起動時シーンを差し替えて再登録する(&mut self, レンダラー: &mut レンダラー, 材料: 起動時シーンの差し替え材料<'_>) -> Result<(), 起動エラー> {
        let 写す材料 = self.地表の層のタイル.写す材料を組む(材料.大域ずらし量, 材料.チャンク一辺);
        let 登録一式 = レンダラーのシーンを差し替える(レンダラー, 材料.シーン, 材料.並べ方, 写す材料, 材料.ゲーム配線)?;
        self.永続束.再登録する(レンダラー, &mut self.可視判定, &mut self.プリミティブ描画項目, 登録一式, 写す材料)
    }
}

/// 動く個体の宣言まで済ませてからレンダラーのシーンを差し替える。台帳へ入れる登録一式を返す。
/// 受け取るのは差し替えるシーンと写し方だけであり、台帳の中身には触れない。
fn レンダラーのシーンを差し替える(
    レンダラー: &mut レンダラー,
    シーン: &blitz_engine::シーンデータ,
    並べ方: crate::cli::描画対象の並べ方,
    写す材料: シーンを描画入力へ写す材料<'_>,
    ゲーム配線: &crate::game::ゲーム配線,
) -> Result<束の登録一式, 起動エラー> {
    let mut 描画入力 = シーンをレンダラー入力に変換する(シーン, 並べ方, 起動時シーンの所有チャンク, 写す材料)?;
    ゲーム配線.束の描画シーン素材へ動く個体を宣言する(起動時シーンの束ID, &mut 描画入力.描画シーン)?;
    レンダラー.シーンを差し替える(描画入力.描画シーン)?;
    Ok(描画入力.登録一式)
}
