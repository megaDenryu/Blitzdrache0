//! 描画入力が借用するあいだだけ台帳の外へ出る2つの受け皿。担当するのは、可視選択とプリミティブ発行が
//! 必ず同じフレームのうちに一緒に出て一緒に戻ることである。
//!
//! 預けるのは、描画が`&mut アプリ`を要るのに対し、描画入力が台帳の中の受け皿を借用で持つためである。
//! 確保した容量を次のフレームへ持ち越すため、2つは描画の成否によらず戻す。
//! 注意: 預けている間の台帳の受け皿は空である。台帳へ選択を読む処理を足すときは、預ける前か戻した後に読む。

use blitz_render::frame_input::プリミティブ発行受け皿;

use super::描画束の台帳;
use crate::app::visibility::可視選択受け皿;
use crate::error::起動エラー;

/// 台帳から出ている2つの受け皿。別々に預けられないよう1つの値で持つ。
pub(in crate::app) struct 預けた受け皿 {
    可視選択: 可視選択受け皿,
    プリミティブ発行: プリミティブ発行受け皿,
}

impl 預けた受け皿 {
    pub(in crate::app) fn 可視選択を見る(&self) -> &可視選択受け皿 {
        &self.可視選択
    }

    pub(in crate::app) fn プリミティブ発行を見る(&self) -> &プリミティブ発行受け皿 {
        &self.プリミティブ発行
    }
}

impl 描画束の台帳 {
    pub(in crate::app) fn 受け皿を預ける(&mut self) -> 預けた受け皿 {
        預けた受け皿 {
            可視選択: self.可視判定.受け皿を預ける(),
            プリミティブ発行: self.プリミティブ描画項目.発行受け皿を預ける(),
        }
    }

    pub(in crate::app) fn 受け皿を戻す(&mut self, 受け皿: 預けた受け皿) {
        self.可視判定.受け皿を戻す(受け皿.可視選択);
        self.プリミティブ描画項目.発行受け皿を戻す(受け皿.プリミティブ発行);
    }

    /// 預けた受け皿へ、今の台帳の全束のプリミティブ描画項目を詰め直す。束の出入りがフレームの合間に起こるため、フレームごとに詰め直す。
    pub(in crate::app) fn 預けた受け皿へ詰め直す(&self, 受け皿: &mut 預けた受け皿) -> Result<(), 起動エラー> {
        self.プリミティブ描画項目.発行受け皿へ詰め直す(&mut 受け皿.プリミティブ発行)
    }
}
