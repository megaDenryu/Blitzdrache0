//! 描画束の台帳の終了時の観測。担当するのは、可視判定の配線が持つ計器を終了時に1回だけ読み出して1つの値にすることである。
//! 呼ばれるのはプロセスの終わりの1回であり、毎フレームの選別とは呼び出し頻度が違う。

use super::描画束の台帳;
use crate::app::visibility::選別の計器;

/// 終了時の報告が読む、描画束の台帳の観測。
pub(crate) struct 描画束の終了時の観測 {
    pub(crate) 個体詳細段切替回数: u64, // 起動から現在までに個体の段が入れ替わった延べ回数
    pub(crate) 可視材料登録数: usize,   // 束の解除で材料と段の記憶が漏れなく消えたことをこの数で見る
    pub(crate) 選別の計器: 選別の計器,  // 最終フレームの選別の計数・距離区分ごとの世界メートル毎テクセル・キャスター候補の距離分布
}

impl 描画束の台帳 {
    pub(in crate::app) fn 終了時の観測を集める(&self) -> 描画束の終了時の観測 {
        描画束の終了時の観測 {
            個体詳細段切替回数: self.可視判定.段切替回数(),
            可視材料登録数: self.可視判定.登録数(),
            選別の計器: self.可視判定.直近の計器(),
        }
    }
}
