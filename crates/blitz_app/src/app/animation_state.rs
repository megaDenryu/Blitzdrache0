//! アニメーション再生状態(判断45・47)。foxシーンのクリップ選択とブレンド、
//! 毎フレームのスキン行列計算を担う。時刻の歩進は呼び出し元(frame.rs)が、その描画で進めた刻み数×基本刻みで行う。

use blitz_engine::{
    animation::{スキン行列を計算する, ブレンドする, 姿勢を評価する},
    アニメーションクリップ, スキンデータ,
};
use blitz_math::秒;

use crate::cli::アニメーションのブレンド係数;

/// ブレンドの主クリップと副クリップの名前(Foxの歩き/走り)。無ければ先頭から順に選ぶ。
const 主クリップ名: &str = "Walk";
const 副クリップ名: &str = "Run";

pub(super) struct アニメーション再生 {
    スキン: スキンデータ,
    クリップa: アニメーションクリップ,
    クリップb: Option<アニメーションクリップ>,
}

impl アニメーション再生 {
    /// クリップが1本も無い(または スキンが無い)シーンでは`None`(静的表示)。
    /// 名前がWalk/Runのクリップを優先し、無ければ先頭の2本を主/副に選ぶ。
    pub(super) fn 生成する(スキン: Option<スキンデータ>, クリップ一覧: Vec<アニメーションクリップ>) -> Option<Self> {
        let スキン = スキン?;
        let mut 残り: Vec<アニメーションクリップ> = クリップ一覧;
        if 残り.is_empty() {
            return None;
        }
        let クリップa = 取り出す(&mut 残り, 主クリップ名);
        let クリップb = if 残り.is_empty() {
            None
        } else {
            Some(取り出す(&mut 残り, 副クリップ名))
        };
        Some(Self {
            スキン,
            クリップa,
            クリップb,
        })
    }

    /// 時刻(秒)とブレンド係数からGPU境界のスキン行列列(列優先4x4の平坦配列)を計算する。
    pub(super) fn スキン行列を計算する(&self, 時刻: 秒, ブレンド: アニメーションのブレンド係数) -> Vec<[f32; 16]> {
        let 姿勢a = 姿勢を評価する(&self.クリップa, &self.スキン, 時刻);
        let 姿勢 = match &self.クリップb {
            Some(クリップb) if !ブレンド.二本目が混ざらないか() => ブレンドする(
                &姿勢a,
                &姿勢を評価する(クリップb, &self.スキン, 時刻),
                ブレンド.姿勢のブレンド係数へ写す(),
            ),
            _ => 姿勢a,
        };
        let 行列一覧 = スキン行列を計算する(&self.スキン, &姿勢);
        行列一覧.列優先配列一覧().iter().map(平坦にする).collect()
    }
}

/// 指定名のクリップがあればそれを、無ければ先頭を取り出す。
/// 前提: 一覧は空でないこと(呼び出し元が確認済み)。
fn 取り出す(一覧: &mut Vec<アニメーションクリップ>, 名前: &str) -> アニメーションクリップ {
    let 添字 = 一覧.iter().position(|クリップ| クリップ.名前 == 名前).unwrap_or(0);
    一覧.swap_remove(添字)
}

fn 平坦にする(列優先: &[[f32; 4]; 4]) -> [f32; 16] {
    let mut 平坦 = [0.0f32; 16];
    for (列添字, 列) in 列優先.iter().enumerate() {
        平坦[列添字 * 4..列添字 * 4 + 4].copy_from_slice(列);
    }
    平坦
}
