//! 植生の検収世界の初期カメラ姿勢。担当するのは、この世界群に共通の構図を決めることである。
//!
//! 植生の群は一辺24メートルの正方領域へ敷かれる。距離45メートル・見下ろし60度にすると、4個体が画面の4分割へ1体ずつ入り、
//! 中央で交わる帯には個体が掛からない。個体の高さ3メートルぶんの遠近のずれは中央から外へ向くため、帯を横切らない。

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::{メートル, ラジアン};

/// 群が敷かれるチャンク中央の局所座標。チャンクの大域原点はX最小・Z最小の角にあるため、一辺100メートルの半分だけ内側である。
const 注視点の水平メートル: f32 = 50.0;

const 方位度: f32 = 0.0;
const 俯角度: f32 = 60.0;
const 距離倍率: f32 = 15.0;

pub(super) fn 姿勢を与える(カメラ: &mut カメラ) {
    カメラ.更新する(カメラインテント {
        ヨー差分: ラジアン::度から(方位度),
        ピッチ差分: ラジアン::度から(俯角度),
        距離倍率,
    });
    カメラ.注視点をずらす(
        メートル::生成する(注視点の水平メートル),
        メートル::生成する(0.0),
        メートル::生成する(注視点の水平メートル),
    );
}
