//! 目視見本の初期カメラ姿勢。担当するのは、この世界1つの構図を決めることである。
//!
//! 材質見本の球は一辺100メートルのチャンクの中央へ、横幅およそ10.5メートルの1列に並ぶ。距離12メートル・俯角14度に置くと、
//! 視点は注視点より2.9メートル上・水平に11.6メートル手前へ立ち、縦視野60度と画面比16対9から横視野は約91度になるため、
//! 列の全体が横幅の半分ほどを占めて写る。俯角を14度に留めるのは、画面の上側へ空を、下側へ地面を入れるためである。
//! 金属の球は上半分に空を、下半分に地面を映すため、この構図でなければ粗さごとのぼけ方が空だけの映り込みで比べられなくなる。
//!
//! 方位を12度ずらすのは、球の列と画面の辺が平行になる構図を避けるためである。平行だと8球が完全に重なる奥行きへ並び、
//! 手前の球が奥の球を隠す。斜めから見ると列に奥行きが出て、8球それぞれの側面が同時に見える。

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::{メートル, ラジアン};

/// この構図を選ばせるシーン名。庭の地面のチャンクへ付けた安定IDと同じ綴りである。
/// 参照: `crates/blitz_asset_compiler/examples/generate_source_assets/terrain_visual_world.rs`
pub(super) const シーン識別子: &str = "terrain_visual";

/// 注視点の水平位置。チャンクの大域原点はX最小・Z最小の角にあるため、一辺100メートルの半分だけ内側が庭の中央になる。
const 注視点の水平メートル: f32 = 50.0;

/// 注視点の高さ。庭の中央の地面はほぼ高さ0にあり、球の中心はそこから0.5メートル上にある。
const 注視点の高さメートル: f32 = 0.5;

const 方位度: f32 = 12.0;
const 俯角度: f32 = 14.0;

/// 既定の距離3メートルを12メートルへ広げる倍率。
const 距離倍率: f32 = 4.0;

pub(super) fn 姿勢を与える(カメラ: &mut カメラ) {
    カメラ.更新する(カメラインテント {
        ヨー差分: ラジアン::度から(方位度),
        ピッチ差分: ラジアン::度から(俯角度),
        距離倍率,
    });
    カメラ.注視点をずらす(
        メートル::生成する(注視点の水平メートル),
        メートル::生成する(注視点の高さメートル),
        メートル::生成する(注視点の水平メートル),
    );
}
