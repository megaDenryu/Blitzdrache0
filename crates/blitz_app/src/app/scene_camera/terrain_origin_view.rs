//! 地形の起点世界の初期カメラ姿勢。担当するのは、この世界1つの構図を決めることである。
//!
//! 地形世界は一辺100メートルのチャンクが5×5に並ぶ。距離150メートル・見下ろし35度にすると、
//! 視点は地表から約86メートル上に立ち、起伏の稜線が地平として画面に入る斜めの構図になる。
//! 距離を伸ばすほど視点は原点から離れ、視点位置がそのまま必要集合の中心になるため、
//! 先読み半径1で常駐する9チャンクの外側を見ることになる。この構図はその境目が地平に来る値である。

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::ラジアン;

const 方位度: f32 = 0.0;
const 俯角度: f32 = 35.0;
const 距離倍率: f32 = 50.0;

pub(super) fn 姿勢を与える(カメラ: &mut カメラ) {
    カメラ.更新する(カメラインテント {
        ヨー差分: ラジアン::度から(方位度),
        ピッチ差分: ラジアン::度から(俯角度),
        距離倍率,
    });
}
