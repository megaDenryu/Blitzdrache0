//! 影の検収世界の初期カメラ姿勢。担当するのは、この世界1つの構図を決めることである。
//!
//! 真後ろから見下ろすのは、床へ落ちた影が画面の中央に来る構図にするためである。

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::ラジアン;

const 方位度: f32 = 180.0;
const 俯角度: f32 = 50.0;
const 距離倍率: f32 = 2.0;

pub(super) fn 姿勢を与える(カメラ: &mut カメラ) {
    カメラ.更新する(カメラインテント {
        ヨー差分: ラジアン::度から(方位度),
        ピッチ差分: ラジアン::度から(俯角度),
        距離倍率,
    });
}
