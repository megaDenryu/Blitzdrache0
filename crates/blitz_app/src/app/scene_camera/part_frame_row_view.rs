//! 部品で組んだ一間四方の骨格の並びの初期カメラ姿勢。担当するのは、この世界1つの構図を決めることである。
//!
//! **この構図の目的は、1つのベイの壁の向きと骨格との境目を人が判定できる大きさで写すことである。** ベイの外寸は
//! 2.40メートル四方・高さ2.60メートルしかなく、家の並びの距離102メートルの構図では画面の縦の40分の1にも満たない。
//! 壁の仕上げ面がどちらを向いているかも、骨格の柱と壁の背面の境目に深度の競合が出ているかも、その大きさでは読めない。
//!
//! 近づけても計器が壊れないのは、**どのベイにも壁3種と骨格の4部品が必ず据わる**ためである。規則が正面へ扉枠付きの壁、
//! 背面へ平壁、左面へ窓壁を必ず入れるため、完全な1棟が視錐台へ入れば4つの群すべてが発行を立てる。
//! 個体数の突き合わせは可視個体の選別の候補数を使い、視錐台に写ったかどうかに依らない。
//!
//! ベイは一辺100メートルのチャンクの中央へ、間隔10メートルの格子で最大10列10行に建つ。注視点を格子の中央へ置き、
//! 距離24メートル・俯角12度に取ると、視点は注視点より5.0メートル上・水平に23.5メートル手前へ立つ。手前の列までは
//! 約14メートルであり、縦視野60度がその距離で16.2メートルを覆うため、高さ2.60メートルのベイが画面の縦の6分の1で写る。
//! 奥の列は視錐台が距離とともに広がるぶん多数が同時に入る。
//!
//! 方位を25度ずらすのは、チャンクの辺と画面の辺が平行になる構図を避けるためである。平行だと手前の1棟が
//! 奥の1棟をちょうど隠し、列の奥行が絵に出ない。

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::{メートル, ラジアン};

/// 注視点の水平位置。チャンクの大域原点はX最小・Z最小の角にあるため、一辺100メートルの半分だけ内側が並びの中央になる。
const 注視点の水平メートル: f32 = 50.0;

/// 注視点の高さ。ベイの高さ2.60メートルの半ばであり、壁の外枠の宣言の高さ1.3メートルと同じ位置である。
const 注視点の高さメートル: f32 = 1.3;

const 方位度: f32 = 25.0;
const 俯角度: f32 = 12.0;

/// 既定の距離3メートルを24メートルへ広げる倍率。
const 距離倍率: f32 = 8.0;

pub(super) fn 姿勢を与える(カメラ: &mut カメラ) {
    カメラ.更新する(カメラインテント {
        ヨー差分: ラジアン::度から(方位度),
        ピッチ差分: ラジアン::度から(俯角度),
        距離倍率,
    });
    カメラ.注視点をずらす(
        メートル::生成する(注視点の水平メートル),
        メートル::生成する(注視点の高さメートル),
        メートル::生成する(注視点の水平メートル),
    );
}
