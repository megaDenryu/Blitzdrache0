//! キツネの世界の初期カメラ姿勢。担当するのは、この世界1つの構図を決めることである。
//!
//! モデルの寸法が大きい(体長約120単位)ため全身が入る距離まで引き、歩きが見える真横の構図にする。

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::ラジアン;

const 方位度: f32 = 90.0;
const 俯角度: f32 = 10.0;
const 距離倍率: f32 = 45.0;

pub(super) fn 姿勢を与える(カメラ: &mut カメラ) {
    カメラ.更新する(カメラインテント {
        ヨー差分: ラジアン::度から(方位度),
        ピッチ差分: ラジアン::度から(俯角度),
        距離倍率,
    });
}
