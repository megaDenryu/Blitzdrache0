//! 部品で組んだ木の並びの初期カメラ姿勢。担当するのは、この世界1つの構図を決めることである。
//!
//! **この構図の目的は、組み上がった木1本の姿を人が判定できる大きさで写すことである。** 8km世界の散布の固定構図では
//! 1本が数画素にしかならず、幹の継ぎ目も枝の出方も葉房の付き方も絵から読み取れない。
//!
//! 木は一辺100メートルのチャンクの中央へ、間隔10メートルの2列2行に立つ。並びの広がりは一辺10メートルであり、
//! 幹の頂は地面から4.88メートル、葉房の頂はおよそ5.4メートルにある。距離18メートル・俯角12度に置くと、視点は
//! 注視点より3.7メートル上・水平に17.6メートル手前へ立ち、縦視野60度が注視点の距離で20.8メートルを覆うため、
//! 4本とも画面へ収まりながら1本が画面の縦の4分の1を超える大きさで写る。
//!
//! 注視点を高さ2.5メートルに置くのは、木の丈のほぼ半ばだからである。地面へ置くと画面の下半分が地面で埋まる。
//!
//! 方位を25度ずらすのは、チャンクの辺と画面の辺が平行になる構図を避けるためである。平行だと手前の2本が
//! 奥の2本をちょうど隠し、4本のうち2本しか見えない。

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::{メートル, ラジアン};

/// 注視点の水平位置。チャンクの大域原点はX最小・Z最小の角にあるため、一辺100メートルの半分だけ内側が並びの中央になる。
const 注視点の水平メートル: f32 = 50.0;

/// 注視点の高さ。葉房の頂までがおよそ5.4メートルであり、その半ばを見る。
const 注視点の高さメートル: f32 = 2.5;

const 方位度: f32 = 25.0;
const 俯角度: f32 = 12.0;

/// 既定の距離3メートルを18メートルへ広げる倍率。
const 距離倍率: f32 = 6.0;

pub(super) fn 姿勢を与える(カメラ: &mut カメラ) {
    カメラ.更新する(カメラインテント {
        ヨー差分: ラジアン::度から(方位度),
        ピッチ差分: ラジアン::度から(俯角度),
        距離倍率,
    });
    カメラ.注視点をずらす(
        メートル::生成する(注視点の水平メートル),
        メートル::生成する(注視点の高さメートル),
        メートル::生成する(注視点の水平メートル),
    );
}
