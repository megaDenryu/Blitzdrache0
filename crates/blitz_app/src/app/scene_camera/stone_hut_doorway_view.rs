//! 屋内の多光源の検収世界の初期カメラ姿勢。担当するのは、戸口ごしに屋内を見る構図1つを決めることである。
//!
//! 小屋はチャンクの中央(50, 50)へ、戸口を世界の+Z軸へ向けて立つ。既定カメラはヨー0・ピッチ0で注視点の+Z側に立つため、
//! 注視点を小屋の中へ据えるだけで視線が戸口を通る。
//!
//! 注視点を小屋の中心・高さ1.2メートルへ置き、距離を4メートルにすると、視点は戸口の面(小屋の中心から+Z側へ1.3メートル)
//! よりさらに2.7メートル手前に立つ。縦視野60度・画面比16対9の横視野92度に対し、幅4メートルの小屋は73度を占め、
//! 幅1メートルの戸口は21度を占める。小屋の正面が画面をほぼ埋め、その中央の戸口の奥に屋内が見える構図になる。
//!
//! 俯角を6度だけ与えるのは、視点を戸口の上端(高さ1.9メートル)より下に保ちながら床を画面へ入れるためである。
//! 俯角を大きくすると視点が上がり、戸口の上の壁が視線を遮って屋内が見えなくなる。

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::{メートル, ラジアン};

/// この構図を選ばせるシーン名。地面のチャンクへ付けた安定IDと同じ綴りである。
/// 参照: `crates/blitz_asset_compiler/examples/generate_source_assets/stone_hut_world.rs`
pub(super) const シーン識別子: &str = "prop_stone_hut_interior";

/// 注視点の水平位置。小屋を据えた位置と同じ値である。
const 注視点の水平メートル: f32 = 50.0;

/// 注視点の高さ。立っている人の目の高さより少し低く、戸口の高さ1.9メートルの内側に収まる。
const 注視点の高さメートル: f32 = 1.2;

const 俯角度: f32 = 6.0;

/// 既定の距離3メートルを4メートルへ広げる倍率。
const 距離倍率: f32 = 4.0 / 3.0;

pub(super) fn 姿勢を与える(カメラ: &mut カメラ) {
    カメラ.更新する(カメラインテント {
        ヨー差分: ラジアン::度から(0.0),
        ピッチ差分: ラジアン::度から(俯角度),
        距離倍率,
    });
    カメラ.注視点をずらす(
        メートル::生成する(注視点の水平メートル),
        メートル::生成する(注視点の高さメートル),
        メートル::生成する(注視点の水平メートル),
    );
}
