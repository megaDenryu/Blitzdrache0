//! クソゲー1本目「キツネの場所巡り」の初期カメラ姿勢。担当するのは、この世界1つの構図を決めることである。
//!
//! 方位を0度に置くのは、「前へ進む」操作の向きがカメラのヨーから決まるためである。ヨーが0のとき前は北を指し、
//! 出発地点の真北にある1つ目の目的地へ、決定的な台本が向きを1度も変えずに歩いて着く
//! (参照: `crates/blitz_app/src/game/scripted_operation.rs`)。
//!
//! 距離9.6メートル・俯角20度に置くと、視点は注視点より3.3メートル上・水平に9メートル手前へ立つ。体長1.2メートルの
//! キツネが画面の高さのおよそ1割5分を占め、高さ3.5メートルの目印の柱はその倍ほどに写る。キツネと、次に向かう
//! 目的地の柱と、その間の地面の起伏が同時に入る構図である。
//!
//! 注視点をずらさないのは、ゲームがプレイヤーの位置を毎フレーム供給し、カメラの注視点をそこへ据えるためである
//! (参照: `crates/blitz_app/src/app/frame/camera_follow.rs`)。ここで与えるのは向きと距離だけである。

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::ラジアン;

/// この構図を選ばせるシーン名。起動時に読むキツネのシーンへ付けた安定IDと同じ綴りである。
/// 参照: `crates/blitz_asset_compiler/examples/compile_assets/world/fox_tour_declaration.rs`
pub(super) const シーン識別子: &str = "terrain_fox_tour";

const 方位度: f32 = 0.0;
const 俯角度: f32 = 20.0;

/// 既定の距離3メートルを9.6メートルへ広げる倍率。
const 距離倍率: f32 = 3.2;

pub(super) fn 姿勢を与える(カメラ: &mut カメラ) {
    カメラ.更新する(カメラインテント {
        ヨー差分: ラジアン::度から(方位度),
        ピッチ差分: ラジアン::度から(俯角度),
        距離倍率,
    });
}
