//! Blender生成の小物を1体だけ原点へ置く検証シーンの初期カメラ姿勢。担当するのは、この接頭辞を持つシーン群の構図である。
//!
//! 小物は原点へ1体だけ置かれ、接地面が原点にあるため既定の姿勢では画面の上半分へ寄る。注視点を体積の中心へ上げて画面中央へ収める。
//! 方位35度・俯角25度は、正面と側面と上面の3面が同時に見える構図である。既定の方向光は3面へ違う角度で当たるため、
//! 3面が違う明るさで写り、立体として読み取れる。距離倍率0.55は既定3メートルを1.65メートルへ寄せ、
//! 縦視野60度で高さ0.8メートルの小物が画面の高さの約4割を占める大きさにする。

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::{メートル, ラジアン};

/// 小物の注視点の高さ。原点は接地面にあるため、一辺0.8メートルの小物では体積の中心がこの高さに来る。
const 注視高さメートル: f32 = 0.4;

pub(super) fn 姿勢を与える(カメラ: &mut カメラ) {
    カメラ.更新する(カメラインテント {
        ヨー差分: ラジアン::度から(35.0),
        ピッチ差分: ラジアン::度から(25.0),
        距離倍率: 0.55,
    });
    カメラ.注視点をずらす(メートル::生成する(0.0), メートル::生成する(注視高さメートル), メートル::生成する(0.0));
}
