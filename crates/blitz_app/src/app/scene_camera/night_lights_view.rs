//! 夜の多光源の検収世界の初期カメラ姿勢。担当するのは、この世界1つの構図を決めることである。
//!
//! 街灯は一辺52.5メートルの正方格子へ並ぶ。距離45メートル・俯角35度に置くと、視点は注視点より25.8メートル上・
//! 水平に36.9メートル手前へ立つ。縦視野60度であるから距離45メートルの位置で高さおよそ52メートルぶんが写り、
//! 画面比16対9の横視野92度で並び全体が横幅へ収まる。
//!
//! 俯角を真上へ寄せないのは、この構図が奥行きの段をまたいで灯を並べるためである。視点から手前の灯までが
//! およそ11メートル、奥の灯までがおよそ63メートルあり、クラスタ格子の奥行きの段が並びの中で何段も切り替わる。
//! 真上から見下ろすと全部の灯がほぼ同じ奥行きへ入り、奥行きの段の効き方が絵にも計器にも出なくなる。

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::{メートル, ラジアン};

/// 注視点の水平位置。チャンクの大域原点はX最小・Z最小の角にあるため、一辺100メートルの半分だけ内側が並びの中央になる。
const 注視点の水平メートル: f32 = 50.0;

const 俯角度: f32 = 35.0;

/// 既定の距離3メートルを45メートルへ広げる倍率。
const 距離倍率: f32 = 15.0;

pub(super) fn 姿勢を与える(カメラ: &mut カメラ) {
    カメラ.更新する(カメラインテント {
        ヨー差分: ラジアン::度から(0.0),
        ピッチ差分: ラジアン::度から(俯角度),
        距離倍率,
    });
    カメラ.注視点をずらす(
        メートル::生成する(注視点の水平メートル),
        メートル::生成する(0.0),
        メートル::生成する(注視点の水平メートル),
    );
}
