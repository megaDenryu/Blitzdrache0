//! 見本の集落の初期カメラ姿勢。担当するのは、この世界1つの構図を決めることである。
//!
//! 集落は一辺100メートルのチャンクの中央へ、半径30.5メートルの杭の輪を外周として作られる。距離54メートル・俯角16度に置くと、
//! 視点は注視点より14.9メートル上・水平に51.9メートル手前へ立ち、縦視野60度が注視点の距離で60メートルを覆うため、
//! 外周の輪が横幅に収まる。俯角を16度に留めるのは、画面の上端が水平より14度上を向き、地平と空が画面の上側に入るためである。
//! 真上から見下ろす構図では空が1画素も写らず、空ありの世界にした意味が絵に出ない。
//!
//! 方位を20度ずらすのは、チャンクの辺と画面の辺が平行になる構図を避けるためである。平行だと格子状に散らした岩の列が
//! 画面の縦横に揃い、決まった配置が絵として目立つ。

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::{メートル, ラジアン};

/// 注視点の水平位置。チャンクの大域原点はX最小・Z最小の角にあるため、一辺100メートルの半分だけ内側が集落の中央になる。
const 注視点の水平メートル: f32 = 50.0;

/// 注視点の高さ。集落の中央の地面は約0.35メートルの高さにあり、そこから人の背丈ぶん上を見る。
const 注視点の高さメートル: f32 = 2.0;

const 方位度: f32 = 20.0;
const 俯角度: f32 = 16.0;

/// 既定の距離3メートルを54メートルへ広げる倍率。
const 距離倍率: f32 = 18.0;

pub(super) fn 姿勢を与える(カメラ: &mut カメラ) {
    カメラ.更新する(カメラインテント {
        ヨー差分: ラジアン::度から(方位度),
        ピッチ差分: ラジアン::度から(俯角度),
        距離倍率,
    });
    カメラ.注視点をずらす(
        メートル::生成する(注視点の水平メートル),
        メートル::生成する(注視点の高さメートル),
        メートル::生成する(注視点の水平メートル),
    );
}
