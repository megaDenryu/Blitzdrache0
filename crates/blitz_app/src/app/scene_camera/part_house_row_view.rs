//! 部品で組んだ家の並びの初期カメラ姿勢。担当するのは、この世界1つの構図を決めることである。
//!
//! 家並みは一辺100メートルのチャンクの中央へ、間隔10メートルの格子で最大10列10行に建つ。家の並びの広がりは
//! 一辺90メートルであり、屋根の頂は地面から約10メートルにある。距離102メートル・俯角24度に置くと、
//! 視点は注視点より41.5メートル上・水平に93.2メートル手前へ立ち、縦視野60度が注視点の距離で117メートルを覆うため、
//! 端の列まで画面へ収まる。
//!
//! **端まで収めることが計器の前提である。** 部品の群はどれも家並みの全体へ広がっているため、一部でも写れば
//! その群の発行は立つ。ただし写る軒が減れば描いた個体数が減るため、絵と計器を同じ実行から採るこの入口では
//! 全体を収める構図を選ぶ。
//!
//! 方位を25度ずらすのは、チャンクの辺と画面の辺が平行になる構図を避けるためである。平行だと格子に並んだ家の列が
//! 画面の縦横に揃い、軒ごとの向きの違いが並びの規則正しさに埋もれる。

use blitz_engine::{カメラ, カメラインテント};
use blitz_math::{メートル, ラジアン};

/// 注視点の水平位置。チャンクの大域原点はX最小・Z最小の角にあるため、一辺100メートルの半分だけ内側が家並みの中央になる。
const 注視点の水平メートル: f32 = 50.0;

/// 注視点の高さ。屋根の頂までが約10メートルであり、その半ばを見る。
const 注視点の高さメートル: f32 = 5.0;

const 方位度: f32 = 25.0;
const 俯角度: f32 = 24.0;

/// 既定の距離3メートルを102メートルへ広げる倍率。
const 距離倍率: f32 = 34.0;

pub(super) fn 姿勢を与える(カメラ: &mut カメラ) {
    カメラ.更新する(カメラインテント {
        ヨー差分: ラジアン::度から(方位度),
        ピッチ差分: ラジアン::度から(俯角度),
        距離倍率,
    });
    カメラ.注視点をずらす(
        メートル::生成する(注視点の水平メートル),
        メートル::生成する(注視点の高さメートル),
        メートル::生成する(注視点の水平メートル),
    );
}
