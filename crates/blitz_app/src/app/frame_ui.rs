//! 画面へ重ねるUI(egui)の1フレームぶんの描画データ組み立て。
//! 触れるフィールドは`据え付け`・`露出`・`ブレンド`に限り、ゲームの画面と計器は世界実行が作った描画供給で受け取る。露出とブレンドはスライダーが書き換えるため可変で渡す。
//! 呼び出しタイミング: `frame`の`一フレーム実行する`が描画入力の作成より前に呼ぶ(同じフレームの描画へスライダーの変更を反映するため)。

use super::screen_installation::画面の据え付け;
use super::アプリ;
use crate::error::起動エラー;
use crate::overlay_ui::画面へ重ねる内容;
use crate::world_execution::contract::描画供給;

impl アプリ {
    /// 重ねるものが1つも無いフレームは`None`(UIの側がeguiを実行せずに答える)。
    pub(super) fn ui描画データを組み立てる(&mut self, 描画供給: 描画供給) -> Result<Option<blitz_render::UI描画データ>, 起動エラー> {
        let 据え付け = 画面の据え付け::描画の最中に借りる(&mut self.据え付け);
        let 内容 = 画面へ重ねる内容 {
            開発パネルの統計: 据え付け.開発パネルの統計を採る(),
            ゲーム画面: 描画供給.画面へ重ねる表示内容,
            移動とカメラの計器: 描画供給.移動とカメラの計器,
        };
        据え付け.ui描画データを作る(内容, &mut self.露出, &mut self.ブレンド)
    }
}
