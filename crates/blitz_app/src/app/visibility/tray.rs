//! 毎フレーム使い回す選択の受け皿。エンジンの選別係と、群ごとの選択の一覧と、そのフレームの計数と、
//! 判定に使った影の解像度密度を持つ。ID列・段のパス別区間・キャスターの距離分布は選別係が所有し、
//! この型は選別係を1つ保持して読み出しを中継する。
//! 同じ型が持つのは、選択が指す区間が必ず同じフレームのID列と区間を指し、計数がその中身を数えた値であり、
//! 解像度密度がその判定に使った正射影の値であるという対応を1箇所で保つためである。
//! 注意: 描画入力が借用するため、預けるときも戻すときもこの型ごと動かす。預けている間の中身は空であり計数も0である。

use blitz_engine::{キャスター距離分布, 可視個体と段の選別係, 可視判定計数};
use blitz_render::{cascade::影の解像度密度, 可視個体選択, 段別描画範囲};

#[derive(Default)]
pub(in crate::app) struct 可視選択受け皿 {
    選別係: 可視個体と段の選別係,
    選択一覧: Vec<可視個体選択>,
    /// そのフレームの全群の計数の合計。判定の内側でしか数えられないため、選択と同じ型が最後の値を保持して報告へ渡す。
    計数: 可視判定計数,
    /// 判定範囲を組み立てたときの解像度密度。1フレームも判定していない間は`None`であり、報告はその事実を語で告げる。
    解像度密度: Option<影の解像度密度>,
}

/// 直近のフレームの計器一式。3つを1つの型で返すのは、別々に取ると違うフレームの値を並べうるためである。
pub(crate) struct 選別の計器 {
    pub(crate) 計数: 可視判定計数,
    pub(crate) 解像度密度: Option<影の解像度密度>,
    pub(crate) 距離分布: キャスター距離分布,
}

impl 可視選択受け皿 {
    pub(super) fn 生成する() -> Self {
        Self::default()
    }

    pub(super) fn 空にする(&mut self) {
        self.選別係.空にする();
        self.選択一覧.clear();
        self.計数 = 可視判定計数::default();
    }

    pub(super) fn 計数を据える(&mut self, 計数: 可視判定計数) {
        self.計数 = 計数;
    }

    pub(super) fn 解像度密度を据える(&mut self, 密度: 影の解像度密度) {
        self.解像度密度 = Some(密度);
    }

    /// 直近のフレームの計器。計数はレンダラーが積んだ発行から数える計数とは出どころが違い、2つを突き合わせることが整合の証拠になる。
    pub(in crate::app) fn 計器(&self) -> 選別の計器 {
        選別の計器 {
            計数: self.計数,
            解像度密度: self.解像度密度,
            距離分布: self.選別係.キャスターの距離分布(),
        }
    }

    /// そのフレームの走査を回す選別係。1フレーム分を選ぶ工程がここから借りて群を1つずつ積む。
    pub(super) fn 選別係を借りる(&mut self) -> &mut 可視個体と段の選別係 {
        &mut self.選別係
    }

    pub(super) fn id列の長さ(&self) -> usize {
        self.選別係.id列の長さ()
    }

    pub(super) fn 段範囲列の長さ(&self) -> usize {
        self.選別係.段範囲列の長さ()
    }

    pub(super) fn 選択を積む(&mut self, 選択: 可視個体選択) {
        self.選択一覧.push(選択);
    }

    pub(in crate::app) fn id列(&self) -> &[u32] {
        self.選別係.id列()
    }

    pub(in crate::app) fn 段範囲列(&self) -> &[段別描画範囲] {
        self.選別係.段範囲列()
    }

    pub(in crate::app) fn 選択一覧(&self) -> &[可視個体選択] {
        &self.選択一覧
    }
}
