//! そのフレームの判定範囲を組み立てる工程。受け取るのはカメラ相対ビュー射影とライティングとカメラ大域原点、
//! 返すのはカメラ視錐台と帯ごとのライト正射影を光空間の直方体として表した組である。
//! ライト側をレンダラーのシャドウパスと同じカスケードの構築結果から導くことがこの工程の要点であり、
//! 呼び出し元は導出の中身を知らずに組を受け取る。判定に使う範囲と実際に描く範囲がずれると影が欠ける。
//! 帯ごとの行列を4つ渡すのは、帯ごとのシャドウパスが自分の帯のライトビュー射影で描くためである。
//! 全4帯を1つで覆う包囲は第5段の暫定であり、帯別カリング(第6段)がこれを置き換えた。
//! 注意: カメラ視錐台を影へ流用してはならない。画面外の個体が画面内へ影を落とすためである。

use blitz_engine::{帯別光空間直方体, 視錐台};
use blitz_math::{クリップ, ワールド, 光源クリップ, 変換, 大域ワールド位置};
use blitz_render::cascade::{帯数, 帯番号};
use blitz_render::ライティング入力;

use crate::error::起動エラー;

pub(super) struct 判定範囲の組 {
    pub(super) カメラ: 視錐台,
    /// 帯ごとのライトビュー射影から導いた直方体。方向光の正射影が覆う範囲そのものである。
    pub(super) 帯別ライト: 帯別光空間直方体,
}

pub(super) fn 組み立てる(
    ビュー射影: 変換<ワールド, クリップ>,
    ライティング: ライティング入力,
    カメラ大域原点: 大域ワールド位置,
) -> Result<判定範囲の組, 起動エラー> {
    // アンカーをカメラ相対へ狭める境界と同じ失敗であるため、同じ破れを2つの型で表さず描画側の型付きエラーで表す。
    let カスケード = ライティング
        .カスケードを組み立てる(カメラ大域原点, ビュー射影)
        .map_err(blitz_render::レンダラーエラー::カスケード構築失敗)?;
    let mut 帯ごとの行列 = Vec::with_capacity(帯数);
    for 番号 in 帯番号::全帯() {
        let ライトビュー射影 = カスケード
            .帯のライトビュー射影(番号, カメラ大域原点)
            .map_err(blitz_render::レンダラーエラー::カメラ相対変換失敗)?;
        帯ごとの行列.push(ライトビュー射影);
    }
    Ok(判定範囲の組 {
        カメラ: 視錐台::カメラ相対ビュー射影から生成する(ビュー射影),
        帯別ライト: 帯別光空間直方体::カメラ相対ライトビュー射影から生成する(配列にする(帯ごとの行列)),
    })
}

fn 配列にする(一覧: Vec<変換<ワールド, 光源クリップ>>) -> [変換<ワールド, 光源クリップ>; 帯数] {
    <[変換<ワールド, 光源クリップ>; 帯数]>::try_from(一覧)
        .unwrap_or_else(|_| panic!("帯ごとのライトビュー射影の件数が帯数と一致するという不変条件に違反した"))
}
