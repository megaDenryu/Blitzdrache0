//! そのフレームの判定範囲を組み立てる工程。受け取るのはカメラ相対ビュー射影とライティングとカメラ大域原点、
//! 返すのはカメラ視錐台と距離区分ごとのライト正射影を光空間の直方体として表した組である。
//! ライト側をレンダラーのシャドウパスと同じ多段の構築結果から導くことがこの工程の要点であり、
//! 呼び出し元は導出の中身を知らずに組を受け取る。判定に使う範囲と実際に描く範囲がずれると影が欠ける。
//! 距離区分ごとの行列を4つ渡すのは、距離区分ごとのシャドウパスが自分の距離区分のライトビュー射影で描くためである。
//! 全4距離区分を1つで覆う包囲は第5段の暫定であり、距離区分別の可視個体の選別(第6段)がこれを置き換えた。
//! 注意: カメラ視錐台を影へ流用してはならない。画面外の個体が画面内へ影を落とすためである。

use blitz_engine::{視錐台, 距離区分別の光空間直方体};
use blitz_math::{クリップ, ワールド, 光源クリップ, 変換, 大域ワールド位置};
use blitz_render::cascade::{影の解像度密度, 距離区分数, 距離区分番号};
use blitz_render::ライティング入力;

use crate::error::起動エラー;

pub(super) struct 判定範囲の組 {
    pub(super) カメラ: 視錐台,
    /// 距離区分ごとのライトビュー射影から導いた直方体。方向光の正射影が覆う範囲そのものである。
    pub(super) 距離区分別のライト: 距離区分別の光空間直方体,
    /// 判定に使った正射影そのものから導いた解像度密度。描いた範囲と別に計算しないため報告と実物がずれない。
    pub(super) 解像度密度: 影の解像度密度,
}

pub(super) fn 組み立てる(
    ビュー射影: 変換<ワールド, クリップ>,
    ライティング: ライティング入力,
    カメラ大域原点: 大域ワールド位置,
) -> Result<判定範囲の組, 起動エラー> {
    // 基準原点をカメラ相対へ狭める境界と同じ失敗であるため、同じ破れを2つの型で表さず描画側の型付きエラーで表す。
    let 多段 = ライティング
        .多段を組み立てる(カメラ大域原点, ビュー射影)
        .map_err(blitz_render::レンダラーエラー::from)?;
    let mut 距離区分ごとの行列 = Vec::with_capacity(距離区分数);
    for 番号 in 距離区分番号::全距離区分() {
        let ライトビュー射影 = 多段
            .距離区分のライトビュー射影(番号, カメラ大域原点)
            .map_err(blitz_render::レンダラーエラー::カメラ相対変換失敗)?;
        距離区分ごとの行列.push(ライトビュー射影);
    }
    Ok(判定範囲の組 {
        カメラ: 視錐台::カメラ相対ビュー射影から生成する(ビュー射影),
        距離区分別のライト: 距離区分別の光空間直方体::カメラ相対ライトビュー射影から生成する(
            配列にする(距離区分ごとの行列),
        ),
        解像度密度: 多段.解像度密度(),
    })
}

fn 配列にする(一覧: Vec<変換<ワールド, 光源クリップ>>) -> [変換<ワールド, 光源クリップ>; 距離区分数] {
    <[変換<ワールド, 光源クリップ>; 距離区分数]>::try_from(一覧)
        .unwrap_or_else(|_| panic!("距離区分ごとのライトビュー射影の件数が距離区分数と一致するという不変条件に違反した"))
}
