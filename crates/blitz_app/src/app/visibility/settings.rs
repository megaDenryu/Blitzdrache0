//! 個体別LODの段を分ける距離の刻みとヒステリシス幅。コンポジションルートであるこのアプリが値を決め、
//! 選択の規則そのものはエンジン側が持つ(地形の`streaming/lod_sync.rs`と同型)。
//! 値をここ1箇所へ置くのは、絵の見え方に直結する調整点が呼び出しの流れの途中に埋もれないようにするためである。

use blitz_engine::{個体LOD選択設定, 段選択方式};
use blitz_math::メートル;

/// 個体の段を1つ粗くする距離の刻み。高さ3メートル前後の個体が、この距離で画面上の高さおよそ数十画素になる。
const 基準距離メートル: f32 = 50.0;

/// 段の切替に持たせる重なりの幅。基準距離の10分の1であり、境界を跨ぐ往復で段が毎フレーム入れ替わらない。
const ヒステリシス幅メートル: f32 = 5.0;

/// 定数が検証を通らない状態はこのファイルの誤りであって実行時の入力の誤りではないため、
/// 回復可能な失敗として上位へ返さず、破られた不変条件として停止する。
pub(super) fn 段の閾値設定を作る() -> 個体LOD選択設定 {
    let 設定 = 個体LOD選択設定::生成する(メートル::生成する(基準距離メートル), メートル::生成する(ヒステリシス幅メートル));
    match 設定 {
        Ok(値) => 値,
        Err(誤り) => panic!("個体LOD選択設定の定数が検証を満たさない: {誤り}"),
    }
}

/// 起動指定から来る選別のつまみ。1つの型へまとめるのは、どれも計測と検収のために本番の選別を部分的に止めるか
/// 本番の選別を観測する同じ性質の指定であり、配線が持つフィールドとして別々に並べる理由が無いためである。
#[derive(Clone, Copy)]
pub(in crate::app) struct 選別のつまみ {
    /// `--no-instance-cull`でfalse。falseは視錐台で絞らず全個体を可視とする。
    pub(in crate::app) 可視判定有効: bool,
    /// `--no-instance-lod`でfalse。falseは全個体を最詳細段で描く。
    pub(in crate::app) 段選択有効: bool,
    /// `--no-instance-shadow`でfalse。falseはどの距離区分も個体を1体も影の候補にしない。
    pub(in crate::app) 影キャスター有効: bool,
    /// `--report-caster-distance`でtrue。trueは選別と同じ判定でキャスター候補のカメラ距離分布を数える走査を1本足す。
    /// 数えるだけであり、どの個体を描くかは1つも変えない。
    pub(in crate::app) キャスター距離分布を数える: bool,
}

/// そのフレームの段選択の方式。段の選択を止めた実行では全個体を最詳細段で描く。
/// 起動指定の真偽から方式へ写すのをここへ置くのは、この判断が距離の刻みと同じ「段をどう選ぶか」の設定であるためである。
pub(super) fn 段選択方式を選ぶ(段選択有効: bool, 設定: 個体LOD選択設定) -> 段選択方式 {
    if 段選択有効 {
        段選択方式::距離とヒステリシス(設定)
    } else {
        段選択方式::最詳細に固定
    }
}
