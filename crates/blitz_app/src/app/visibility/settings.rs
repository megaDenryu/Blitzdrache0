//! 個体別LODの段を分ける距離の刻みとヒステリシス幅。コンポジションルートであるこのアプリが値を決め、
//! 選択の規則そのものはエンジン側が持つ(地形の`streaming/lod_sync.rs`と同型)。
//! 値をここ1箇所へ置くのは、絵の見え方に直結する調整点が呼び出しの流れの途中に埋もれないようにするためである。

use blitz_engine::個体LOD選択設定;
use blitz_math::メートル;

/// 個体の段を1つ粗くする距離の刻み。高さ3メートル前後の個体が、この距離で画面上の高さおよそ数十画素になる。
const 基準距離メートル: f32 = 50.0;

/// 段の切替に持たせる重なりの幅。基準距離の10分の1であり、境界を跨ぐ往復で段が毎フレーム入れ替わらない。
const ヒステリシス幅メートル: f32 = 5.0;

/// 定数が検証を通らない状態はこのファイルの誤りであって実行時の入力の誤りではないため、
/// 回復可能な失敗として上位へ返さず、破られた不変条件として停止する。
pub(super) fn 段の閾値設定を作る() -> 個体LOD選択設定 {
    let 設定 = 個体LOD選択設定::生成する(メートル::生成する(基準距離メートル), メートル::生成する(ヒステリシス幅メートル));
    match 設定 {
        Ok(値) => 値,
        Err(誤り) => panic!("個体LOD選択設定の定数が検証を満たさない: {誤り}"),
    }
}
