//! そのフレームの2つの視錐台を組み立てる工程。受け取るのはカメラ相対ビュー射影とライティングとカメラ大域原点、
//! 返すのはカメラ視錐台とライト視錐台の組である。
//! ライト側をレンダラーのシャドウパスと同じライトビュー射影から導くことがこの工程の要点であり、
//! 呼び出し元は導出の中身を知らずに組を受け取る。判定に使う視錐台と実際に描く範囲がずれると影が欠ける。
//! 注意: カメラ視錐台をシャドウへ流用してはならない。画面外の個体が画面内へ影を落とすためである。

use blitz_engine::視錐台;
use blitz_math::{クリップ, ワールド, 変換, 大域ワールド位置};
use blitz_render::ライティング入力;

use crate::error::起動エラー;

pub(super) struct 視錐台の組 {
    pub(super) カメラ: 視錐台,
    pub(super) ライト: 視錐台,
}

pub(super) fn 組み立てる(
    ビュー射影: 変換<ワールド, クリップ>,
    ライティング: ライティング入力,
    カメラ大域原点: 大域ワールド位置,
) -> Result<視錐台の組, 起動エラー> {
    // アンカーをカメラ相対へ狭める境界と同じ失敗であるため、同じ破れを2つの型で表さず描画側の型付きエラーで表す。
    let ライトビュー射影 = ライティング
        .ライトビュー射影を組み立てる(カメラ大域原点)
        .map_err(blitz_render::レンダラーエラー::カメラ相対変換失敗)?;
    Ok(視錐台の組 {
        カメラ: 視錐台::カメラ相対ビュー射影から生成する(ビュー射影),
        ライト: 視錐台::カメラ相対ライトビュー射影から生成する(ライトビュー射影),
    })
}
