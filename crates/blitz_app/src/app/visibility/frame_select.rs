//! 1フレーム分の群ごとの選択を回す工程。受け取るのはそのフレームの視錐台とカメラ大域原点と2つの方式、
//! 書き換えるのは台帳の段の記憶と受け皿だけであり、返すのは全群の計数を足し合わせた値である。
//! 判定と選択の規則そのものはエンジン側が持ち、ここは群を順に取り出して呼び、選択の区間を受け皿へ積むことを担う。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」「個体別LOD」

use blitz_engine::{
    キャスターのカメラ距離分布を数える, 個体選択材料, 可視個体と段を選ぶ, 可視判定方式, 可視判定計数, 段選択方式, 視錐台, 距離区分別の光空間直方体,
    距離区分別の可視判定,
};
use blitz_math::大域ワールド位置;
use blitz_render::可視個体選択;

use super::registry::群可視材料台帳;
use super::settings::選別のつまみ;
use super::tray::可視選択受け皿;
use crate::error::起動エラー;

pub(super) struct 選択の条件<'a> {
    pub(super) 視錐台: 視錐台,
    /// 距離区分ごとのシャドウパスがそのフレームに使うライトビュー射影から導いた直方体。共有の光基底で持つ。
    pub(super) 距離区分別のライト: 距離区分別の光空間直方体,
    pub(super) カメラ大域原点: 大域ワールド位置,
    /// 起動指定で切る選別のつまみ。可視判定と影の候補の有無、および距離分布を数えるかがここから来る。
    pub(super) つまみ: 選別のつまみ,
    pub(super) 段選択: 段選択方式,
    pub(super) 台帳: &'a mut 群可視材料台帳,
    pub(super) 受け皿: &'a mut 可視選択受け皿,
}

pub(super) fn 一フレーム分を選ぶ(条件: &mut 選択の条件<'_>) -> Result<可視判定計数, 起動エラー> {
    let mut 計数 = 可視判定計数::default();
    for (束id, 登録) in 条件.台帳.走査する() {
        // 基準原点をカメラ相対へ狭める境界はレンダラーの描画対象と同じであり、失敗する条件も同じである。
        // 同じ破れを2つの型で表さないため、描画側の型付きエラーで表す。
        let 基準原点 = 登録
            .大域の基準原点()
            .カメラ相対へ変換する(条件.カメラ大域原点)
            .map_err(blitz_render::レンダラーエラー::カメラ相対変換失敗)?;
        let id列開始 = 条件.受け皿.id列の長さ();
        let 段範囲開始 = 条件.受け皿.段範囲列の長さ();
        let 対象添字 = 登録.対象添字();
        let (群材料, 状態) = 登録.材料と段状態を借りる();
        let 段数 = 状態.段数();
        let 材料 = 個体選択材料 {
            シーン可視判定: if 条件.つまみ.可視判定有効 {
                可視判定方式::視錐台で絞る(&条件.視錐台)
            } else {
                可視判定方式::全個体を可視とする
            },
            距離区分別の可視判定: 影の判定を選ぶ(条件.つまみ.影キャスター有効, 条件.つまみ.可視判定有効, &条件.距離区分別のライト),
            材料: 群材料,
            カメラ相対の基準原点: 基準原点,
            段選択: 条件.段選択,
        };
        計数 = 計数.足し合わせる(可視個体と段を選ぶ(&材料, 状態, 条件.受け皿.段別受け皿を借りる()));
        if 条件.つまみ.キャスター距離分布を数える {
            キャスターのカメラ距離分布を数える(&材料, 条件.受け皿.距離分布を借りる());
        }
        // 列の長さは可視の有無で群ごとに変わるため、選択の区間は積んだ後の長さの差から取る。
        let id列長 = 条件.受け皿.id列の長さ() - id列開始;
        条件
            .受け皿
            .選択を積む(可視個体選択::生成する(*束id, 対象添字, id列開始, id列長, 段範囲開始, 段数));
    }
    Ok(計数)
}

/// そのフレームの影の候補の決め方。キャスター0の対照は可視判定の有無より先に効く。
/// 影を落とさないことと全個体が影を落とすことを1つの真偽で表せないため、2つのつまみから3つの方式へ写す。
fn 影の判定を選ぶ(
    影キャスター有効: bool, 可視判定有効: bool, ライト: &距離区分別の光空間直方体
) -> 距離区分別の可視判定<'_> {
    if !影キャスター有効 {
        return 距離区分別の可視判定::全距離区分で影を落とさない;
    }
    if 可視判定有効 {
        return 距離区分別の可視判定::距離区分ごとの直方体で絞る(ライト);
    }
    距離区分別の可視判定::全距離区分で全個体を可視とする
}
