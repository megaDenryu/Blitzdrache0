//! 束の追加と解除で出入りする可視材料の台帳。触れるのは登録の一覧だけであり、毎フレームの判定は行わない。
//! 読込・解除の局面と毎フレームの判定の局面で呼ばれる頻度も契機も違うため、同じ型に混ぜず分けている。
//! 注意: 1つの束の登録は必ずまとめて入り、まとめて出る。束の一部だけが残ると、存在しない描画対象の選択を作り続ける。

use blitz_render::描画束ID;

use super::registration::群可視材料の登録;

#[derive(Default)]
pub(super) struct 群可視材料台帳 {
    登録一覧: Vec<(描画束ID, 群可視材料の登録)>,
}

impl 群可視材料台帳 {
    /// 描画束をレンダラーへ追加した直後に呼ぶ。束が持たない群は登録が0件になり、その束の対象は全個体を最詳細段で描く。
    pub(super) fn 束を登録する(&mut self, 束id: 描画束ID, 登録一覧: Vec<群可視材料の登録>) {
        self.束を解除する(束id);
        self.登録一覧.extend(登録一覧.into_iter().map(|登録| (束id, 登録)));
    }

    /// 描画束の解除を予約した時点で呼ぶ。レンダラーがその束を描かなくなった後も材料が残ると、
    /// 存在しない束の選択を毎フレーム作り続ける。
    pub(super) fn 束を解除する(&mut self, 束id: 描画束ID) {
        self.登録一覧.retain(|(登録済みid, _)| *登録済みid != 束id);
    }

    /// シーン差し替えは全束を作り直すため、材料も全部捨てる。
    pub(super) fn 全束を解除する(&mut self) {
        self.登録一覧.clear();
    }

    pub(super) fn 走査する(&mut self) -> impl Iterator<Item = &mut (描画束ID, 群可視材料の登録)> {
        self.登録一覧.iter_mut()
    }

    pub(super) fn 段切替回数(&self) -> u64 {
        self.登録一覧.iter().map(|(_, 登録)| 登録.段切替回数()).sum()
    }

    /// 現在登録されている群の件数。束の解除で材料と段の記憶が漏れなく消えたことを、実行の外からこの数で見る。
    pub(super) fn 登録数(&self) -> usize {
        self.登録一覧.len()
    }
}
