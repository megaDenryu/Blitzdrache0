//! 1つのインスタンス群を可視判定へ登録するための材料一式。束IDは登録の側が付けるため持たない。
//! 描画対象添字は束の中での並び順であり、レンダラーが描画対象資源を作る順序と一致する。
//! 大域アンカーを持つのは、材料の座標がアンカー基準であり、毎フレームここからカメラ相対アンカーを作るためである。

use blitz_engine::群可視材料;
use blitz_math::大域ワールド位置;

pub(crate) struct 群可視材料の登録 {
    対象添字: usize,
    大域アンカー: 大域ワールド位置,
    材料: 群可視材料,
}

impl 群可視材料の登録 {
    pub(crate) fn 生成する(対象添字: usize, 大域アンカー: 大域ワールド位置, 材料: 群可視材料) -> Self {
        Self {
            対象添字,
            大域アンカー,
            材料,
        }
    }

    pub(super) fn 対象添字(&self) -> usize {
        self.対象添字
    }

    pub(super) fn 大域アンカー(&self) -> 大域ワールド位置 {
        self.大域アンカー
    }

    pub(super) fn 材料(&self) -> &群可視材料 {
        &self.材料
    }
}
