//! 1つのインスタンス群を可視判定と段選択へ登録するための材料一式。束IDは登録の側が付けるため持たない。
//! 描画対象添字は束の中での並び順であり、レンダラーが描画対象資源を作る順序と一致する。
//! 大域アンカーを持つのは、材料の座標がアンカー基準であり、毎フレームここからカメラ相対アンカーを作るためである。
//! 個体別の段の記憶を同じ型が持つのは、記憶の長さが群の個体数と一致しなければならず、束の追加と解除で
//! 材料と記憶が別々に生き死にすると長さが食い違うためである。

use blitz_engine::{個体別段状態, 群可視材料};
use blitz_math::大域ワールド位置;

pub(crate) struct 群可視材料の登録 {
    対象添字: usize,
    大域アンカー: 大域ワールド位置,
    材料: 群可視材料,
    段状態: 個体別段状態,
}

impl 群可視材料の登録 {
    pub(crate) fn 生成する(
        対象添字: usize, 大域アンカー: 大域ワールド位置, 材料: 群可視材料, 段状態: 個体別段状態
    ) -> Self {
        Self {
            対象添字,
            大域アンカー,
            材料,
            段状態,
        }
    }

    pub(super) fn 対象添字(&self) -> usize {
        self.対象添字
    }

    pub(super) fn 大域アンカー(&self) -> 大域ワールド位置 {
        self.大域アンカー
    }

    /// 材料と段の記憶を同時に借りる。1回の走査が材料を読みながら記憶を書き換えるため、2つに分けて借りると
    /// 借用が重なる。同じ登録の別々のフィールドであることをここで示す。
    pub(super) fn 材料と段状態を借りる(&mut self) -> (&群可視材料, &mut 個体別段状態) {
        (&self.材料, &mut self.段状態)
    }

    pub(super) fn 段切替回数(&self) -> u64 {
        self.段状態.切替回数()
    }
}
