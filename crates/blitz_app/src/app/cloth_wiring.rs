//! 布の配線。布プリセット・布の参照比較・掴みの介入は1つの機能の寿命を共有し、起動時に揃って据わり、
//! 布を持たない起動ではどれも空である。命令は毎描画の入力を作ることと、終了時に参照計算と突き合わせることの2つである。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断11」。
//!
//! 布の毎フレーム入力(判断53・54・56)。カプセルと掴み写像はシナリオごとの布プリセットから取る。
//! 掴む介入: マウス右押下中、掴み粒子(布の下端行の左端)の目標拘束をカーソル位置から写した目標へ毎フレーム有効にし、
//! 離した最初のフレームで無効にする(掴み状態バッファを持たない設計)。
//!
//! その描画で進める刻み数を布へ渡すのは、布シミュレーションが固定刻みで必ず進む区分に属するためである。
//! 描画ごとに1回進める形は、布の進む速さが画面の書き換え頻度に比例する欠陥を残す。
//! 参照: `_doc/設計/時間の規律.md`「判断5」。
//!
//! `アプリ`が自分のフィールドから材料を集めてこの配線へ渡す口も、同じ機能の配線であるためここに置く。

mod grab_intervention;
#[cfg(test)]
mod grab_intervention_tests;

use winit::dpi::PhysicalSize;

use blitz_math::{メートル, ワールド, 位置};
use blitz_render::{レンダラー, 布の進める刻み数, 布フレーム入力};

use super::cloth_reference::布の参照比較;
use super::cloth_setup::布プリセット;
use super::screen_installation::画面の据え付け;
use super::アプリ;
use crate::app::進める刻み数;
use crate::error::起動エラー;

use grab_intervention::掴み介入の発行;

pub(in crate::app) struct 布の配線 {
    プリセット: Option<布プリセット>,
    参照比較: Option<布の参照比較>, // XPBDの参照比較の方式だけが持つ。終了時にCPUの参照計算と突き合わせる
    掴みの介入: 掴み介入の発行,     // 掴み操作を布の介入へ写す発行元
}

impl 布の配線 {
    /// 布の題材はカタログを読んで初めて決まるため、起動の最初は布を1つも持たない状態で始める。
    pub(in crate::app) fn 布を持たない状態から始める() -> Self {
        Self {
            プリセット: None,
            参照比較: None,
            掴みの介入: 掴み介入の発行::掴んでいない状態から始める(),
        }
    }

    pub(in crate::app) fn 起動時に据える(&mut self, プリセット: Option<布プリセット>, 参照比較: Option<布の参照比較>) {
        self.プリセット = プリセット;
        self.参照比較 = 参照比較;
    }

    pub(in crate::app) fn この描画の入力を作る(&mut self, 掴み: Option<(f32, f32)>, 物理寸法: PhysicalSize<u32>, 刻み数: 進める刻み数) -> Result<Option<布フレーム入力>, 起動エラー> {
        let Some(プリセット) = &self.プリセット else {
            return Ok(None);
        };
        let (カプセル端点a, カプセル端点b, カプセル半径) = プリセット.カプセル.unwrap_or(([0.0; 3], [0.0; 3], 0.0));
        let 目標位置 = 掴みの目標位置を求める(掴み, 物理寸法, プリセット);
        let 介入一覧 = self.掴みの介入.この描画の介入一覧を作る(目標位置, プリセット.掴みの目標拘束添字, 刻み数);
        if let Some(比較) = &mut self.参照比較 {
            比較.刻みを数える(刻み数);
        }
        let 介入件数 = u32::try_from(介入一覧.len()).unwrap_or_else(|_| panic!("介入件数がu32に収まらない"));
        let 進める刻み数 = 布の進める刻み数::生成する(u32::from(刻み数.本数())).map_err(blitz_render::レンダラーエラー::from)?;
        Ok(Some(布フレーム入力 {
            進める刻み数,
            カプセル端点a,
            カプセル端点b,
            カプセル半径,
            介入バイト列: blitz_sim::バイト列にする(&介入一覧),
            介入件数,
        }))
    }

    /// 参照比較の方式で起動したときだけ、GPUの布を読み戻してCPUの参照計算と突き合わせる行を出す。
    /// レンダラーを受け取って読み戻すのは、突き合わせない起動で読み戻し(GPUの全作業の待ち)を起こさないためである。
    pub(in crate::app) fn 終了時に参照計算と突き合わせる(&self, レンダラー: Option<&レンダラー>) {
        let Some(比較) = &self.参照比較 else {
            return;
        };
        let 読み戻し = レンダラー.map(レンダラー::布の粒子と乗数を読み戻す);
        crate::reports::cloth_xpbd_reference::参照比較を表示する(比較, 読み戻し);
    }
}

impl アプリ {
    /// 毎描画の布の入力。`アプリ`が持つ入力状態とウィンドウの寸法を集めて布の配線へ渡す。
    pub(super) fn この描画の布入力を作る(&mut self, 刻み数: 進める刻み数) -> Result<Option<布フレーム入力>, 起動エラー> {
        let 物理寸法 = 画面の据え付け::描画の最中に見る(&self.据え付け).ウィンドウの物理寸法();
        self.布の配線.この描画の入力を作る(self.入力状態.掴み操作(), 物理寸法, 刻み数)
    }
}

/// 掴んでいる描画だけ、カーソル位置(物理px)をプリセットの写像でワールドの目標位置へ写す。
fn 掴みの目標位置を求める(掴み: Option<(f32, f32)>, 物理寸法: PhysicalSize<u32>, プリセット: &布プリセット) -> Option<位置<ワールド>> {
    let (px, py) = 掴み?;
    Some(目標位置へ写す(プリセット, px, py, 物理寸法.width, 物理寸法.height))
}

/// カーソル位置(物理px)をプリセットの写像(中心+横基底*x正規化座標+縦基底*y正規化座標)でワールドへ写す。
/// レイキャストは導入しない(判断53の最小実装)。生の3成分を座標系つきの位置へ包む境界はここである。
fn 目標位置へ写す(プリセット: &布プリセット, px: f32, py: f32, 幅: u32, 高さ: u32) -> 位置<ワールド> {
    let x正規化座標 = (px / ウィンドウ寸法を実数へ変換する(幅)) * 2.0 - 1.0;
    let y正規化座標 = 1.0 - (py / ウィンドウ寸法を実数へ変換する(高さ)) * 2.0;
    let 写像 = &プリセット.掴み;
    let 成分 = |軸: usize| メートル::生成する(写像.中心[軸] + 写像.横基底[軸] * x正規化座標 + 写像.縦基底[軸] * y正規化座標);
    位置::生成する(成分(0), 成分(1), 成分(2))
}

/// 前提: ウィンドウ寸法は実運用で65535を超えない(draw_commandsのu16経由変換と同じ根拠)。
fn ウィンドウ寸法を実数へ変換する(値: u32) -> f32 {
    f32::from(u16::try_from(値).unwrap_or_else(|_| panic!("ウィンドウ寸法がu16に収まらない: {値}")))
}
