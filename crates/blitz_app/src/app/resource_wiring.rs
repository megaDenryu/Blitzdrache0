//! 資源の配線。外から来た新しいデータを描画へ載せる責務を共有する2つ(ホットリローダーとチャンクのストリーミング)を
//! 1つの型が持つ。どちらも、実行中に届いた新しい実行時アセットをレンダラーと描画束の台帳へ載せる工程であり、
//! ストリーミングの進行はホットリローダーが預かる実行時カタログを読む。2つを別々に持つと、その依存が呼び出し側の
//! 引数の並びに現れる。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断11」
//!
//! レンダラーと描画束の台帳はこの型が保持せず、命令ごとに引数で受ける。どちらも別の階層が所有するためである。
//! ホットリロードの確認は`hot_reload_check`と`asset_apply`、毎フレームのストリーミングの進行は`streaming_advance`が持つ。

mod asset_apply;
mod hot_reload_check;
mod streaming_advance;

use blitz_engine::チャンク一辺;
use blitz_render::地形詳細段選択;

use super::streaming::{ストリーミングの有無, ストリーミング要約, ストリーミング配線};
use crate::hot_reload::ホットリローダー;
use crate::world_execution::contract::読込済みチャンクの形の出どころ;

pub(in crate::app) struct 資源の配線 {
    ホットリローダー: ホットリローダー,
    ストリーミング: ストリーミングの有無, // `--streaming`指定時だけ配線を持つ
}

impl 資源の配線 {
    pub(in crate::app) fn 生成する(ホットリローダー: ホットリローダー, ストリーミング: ストリーミングの有無) -> Self {
        Self {
            ホットリローダー, ストリーミング
        }
    }

    /// 起動時のシェーダーのコンパイルと監視の開始を頼む窓口が借りる。
    pub(in crate::app) fn ホットリローダーを可変で借りる(&mut self) -> &mut ホットリローダー {
        &mut self.ホットリローダー
    }

    /// 世界がチャンクを持つときの一辺。ストリーミングを使わない起動では`None`である。
    pub(in crate::app) fn チャンク一辺(&self) -> Option<チャンク一辺> {
        self.ストリーミング.配線を借りる().map(ストリーミング配線::一辺)
    }

    /// その描画の読込済みチャンクの形の出どころ。刻みを回す工程とカメラの遮蔽の工程が同じ組み方を共有する。
    pub(in crate::app) fn 読込済みチャンクの形の出どころを組む(&self) -> 読込済みチャンクの形の出どころ<'_> {
        self.ストリーミング.読込済みチャンクの形の出どころを組む()
    }

    /// そのフレームで各描画束が描く詳細段の受け皿を、描画入力が借用している間だけ預ける。ここに無い束は最詳細段を描く。
    /// ストリーミングを使わない起動は束別の段を1つも持たないため、空の受け皿を返す。
    pub(in crate::app) fn 地形詳細段選択を預かる(&mut self) -> Vec<地形詳細段選択> {
        self.ストリーミング.配線を可変で借りる().map_or_else(Vec::new, ストリーミング配線::地形詳細段選択を預かる)
    }

    pub(in crate::app) fn 地形詳細段選択を返す(&mut self, 受け皿: Vec<地形詳細段選択>) {
        if let Some(配線) = self.ストリーミング.配線を可変で借りる() {
            配線.地形詳細段選択を返す(受け皿);
        }
    }

    /// 固定経路実行で観測した転送量・処理時間・最大使用量。`--streaming`が無ければ調停自体が無く`None`である。
    /// 見送りフレーム数はレンダラーの計器であり配線は保持しないため、呼び出し側が渡す。
    pub(in crate::app) fn ストリーミング要約を作る(&self, 見送りフレーム数: u64) -> Option<ストリーミング要約> {
        self.ストリーミング.配線を借りる().map(|配線| 配線.要約を作る(見送りフレーム数))
    }
}
