//! 終了時の観測一式。プロセスの終わりに1回だけ、各束(描画束の台帳・資源の配線・検収の観測・視点の配線・天空・世界実行・
//! 据え付けのレンダラー)から観測を集めて1つの材料にする局面である。組み立ては`アプリ`の工程配線の仕事であり、
//! 行の整形と出す順序は`reports::exit_report`が持つ。
//!
//! 材料を1つにするのは、30あった照会メソッドを`アプリ`の公開面から消し、`main.rs`が呼ぶ口を5つに留めるためである
//! (参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断11」)。レンダラーを借用で持つのは、計器の多くがレンダラーの内部を
//! 借用で返し、レンダラーの破棄より前に読む必要があるためである。
//!
//! 注意: この材料はレンダラーを借用しているため、`据え付けを破棄する`より前に組んで使い切る。

use blitz_math::大域ワールド位置;
use blitz_render::レンダラー;

use super::draw_bundle_ledger::描画束の終了時の観測;
use super::report_requests::報告要求;
use super::screen_installation::画面の据え付け;
use super::streaming::ストリーミング要約;
use super::time_of_day::天空の終了時の観測;
use super::verification_observation::検収の観測の統計;
use super::アプリ;
use crate::world_execution::contract::ゲーム進行の要約;

pub(crate) struct 終了時の観測一式<'a> {
    pub(crate) 報告要求: &'a 報告要求,
    pub(crate) ゲームの進行: Option<ゲーム進行の要約>, // ゲームを遊ばない起動では無い
    pub(crate) カメラ大域位置: 大域ワールド位置,
    pub(crate) レンダラー: Option<&'a レンダラー>, // 1フレームも描いていない実行では据え付け自体が無い
    pub(crate) 描画束: 描画束の終了時の観測,
    pub(crate) 検収の観測: 検収の観測の統計,
    pub(crate) 天空: 天空の終了時の観測<'a>,
    pub(crate) ストリーミング要約: Option<ストリーミング要約>, // `--streaming`が無ければ調停自体が無い
}

impl アプリ {
    /// 各束から観測を1回だけ集める。レンダラーの破棄より前に呼ぶ。
    pub(super) fn 終了時の観測一式を集める(&self) -> 終了時の観測一式<'_> {
        let レンダラー = self.据え付け.as_ref().map(画面の据え付け::レンダラーを見る);
        let 見送りフレーム数 = レンダラー.map_or(0, レンダラー::見送りフレーム数を取得する);
        終了時の観測一式 {
            報告要求: self.検収の起動設定.報告要求(),
            ゲームの進行: self.世界実行.進行の要約を作る(self.時間進行.現在の固定刻みの番号()),
            カメラ大域位置: super::view_wiring::カメラ大域位置を組み立てる(self.視点.視点ワールド位置(), self.大域ずらし量),
            レンダラー,
            描画束: self.描画束の台帳.終了時の観測を集める(),
            検収の観測: self.検収の観測.終了時の統計を作る(),
            天空: self.天空.終了時の観測を集める(),
            ストリーミング要約: self.資源の配線.ストリーミング要約を作る(見送りフレーム数),
        }
    }
}
