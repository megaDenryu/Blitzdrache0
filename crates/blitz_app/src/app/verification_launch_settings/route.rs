//! この描画をどの検収の経路へ通すかの答え。担当するのは、検収の起動設定が判定した結果を、実行の側が据え付けと
//! 観測だけを触って進められる形で運ぶことだけである。判定の材料も判定の順序も持たない。
//!
//! 6つの経路を1つの判別共用体にするのは、どれか1つだけへ進むことが型の上で決まり、`if`の連鎖で2つの経路が
//! 同時に立つ組み合わせを実行の側が考えなくて済むためである。ダンプの経路が書き出し先を持つのは、名前の付け方が
//! 3つの条件(段差の走査・差し替え前・先行フレーム)から決まる判定であり、実行の側がそのどれかを取りこぼすと
//! 2枚の絵が同じ名前へ重なって片方が消えるためである。

use std::path::PathBuf;

use crate::cli::書き出す画像;
use crate::reports::local_visibility::合成深度の形;

/// この描画が進む検収の経路。
pub(in crate::app) enum 検収の経路 {
    局所可視性 { 形: 合成深度の形 },                    // 合成深度を注入して局所可視度を読み戻し、CPU正本と突き合わせる
    動きベクトル,                                       // 動きベクトルを読み戻して要約を出す
    時間再構成の突き合わせ,                             // 合成入力を注入してCPU正本とGPUの再構成後の色を突き合わせる
    時間再構成の観測 { 局面: 時間再構成の観測の局面 },  // 圧縮前のHDRを読み戻してフレーム間差分か無効化直後の一致を見る
    ダンプ { 画像: 書き出す画像, 書き出し先: PathBuf }, // 読み戻した画像を外部形式へ書き出し、代表画素を照合する
    通常,                                               // 自己操作に応じた描画と画素判定
}

/// 時間再構成の観測がこの描画で何を見るか。最終フレームだけが履歴を無効にして3回描く。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(in crate::app) enum 時間再構成の観測の局面 {
    フレーム間差分, // 1フレーム描いて再構成後の結果を読み戻し、前のフレームの結果との差を並べる
    無効化直後,     // 履歴を無効にしてから3回描き、無効化直後の結果と今の色の一致と決定性の要約値を出す
}
