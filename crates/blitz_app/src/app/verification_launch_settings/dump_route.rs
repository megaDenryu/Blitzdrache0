//! ダンプの経路の判定。担当するのは「この描画で読み戻した画像を書き出すか」と「書き出すならどのファイル名へか」の
//! 2つであり、読み戻しも書き出しも行わない。
//!
//! 名前の付け方をこの判定へ集めるのは、後置きを足す条件が3つあり(段差の走査・差し替え前・先行フレーム)、
//! 実行の側がそのどれかを取りこぼすと、2枚の絵が同じ名前へ重なって片方が消えるためである。

use std::path::{Path, PathBuf};

use super::route::検収の経路;
use super::検収の起動設定;
use crate::app::time_of_day::撮影の有無;
use crate::app::time_step::描画機会の番号;
use crate::smoke::スモークアクション;

/// 差し替え前のフレームへ足す後置き。
const 差し替え前の後置き: &str = "_before";
/// 同一起動内の再現性を見るために撮る、最終フレームの1つ前へ足す後置き。
const 先行フレームの後置き: &str = "_preceding";

impl 検収の起動設定 {
    /// フレームダンプが指定され、かつ`--frames`の最終フレームか差し替え前の絵を採るフレームか先行フレームなら、ダンプの経路を返す。
    /// 段差の走査では撮影ごとの最後のフレームが対象であり、そちらは撮影の有無が答える。
    ///
    /// 前提: 段差の走査が書き出し先を持つことは起動引数の解析が確かめる(`crate::cli::走査の書き出し先を確かめる`)。
    /// 撮影の読み戻しのフレームでダンプ先が無い組み合わせは作られないため、その場合にこの判定が通常を返すことは到達しない。
    pub(super) fn ダンプの経路を選ぶ(&self, 描画機会の番号: 描画機会の番号, スモークの描画機会の数: Option<u32>, 自己操作: スモークアクション, 撮影: 撮影の有無) -> Option<検収の経路> {
        let 画像 = self.フレームダンプ先.書き出す画像()?;
        let 基準名 = self.フレームダンプ先.基準名()?;
        let 先行フレームか = self.読み戻し検収.先行フレームも書き出すか && スモークの描画機会の数.is_some_and(|描画機会の数| 描画機会の番号.最後の一つ前の描画機会か(描画機会の数));
        let 差し替え前か = 自己操作 == スモークアクション::差し替え前ダンプ;
        let 最終フレームか = スモークの描画機会の数.is_some_and(|描画機会の数| 描画機会の番号.最後の描画機会か(描画機会の数));
        let 書き出し先 = match 撮影 {
            撮影の有無::撮っている {
                撮影, このフレームで読み戻すか: true
            } => 後置きを足す(基準名, 撮影.ファイル名の後置き().as_str()),
            撮影の有無::撮っている {
                このフレームで読み戻すか: false, ..
            }
            | 撮影の有無::撮っていない => {
                if 先行フレームか {
                    後置きを足す(基準名, 先行フレームの後置き)
                } else if 差し替え前か {
                    後置きを足す(基準名, 差し替え前の後置き)
                } else if 最終フレームか {
                    基準名.to_path_buf()
                } else {
                    return None;
                }
            }
        };
        Some(検収の経路::ダンプ { 画像, 書き出し先 })
    }
}

/// 拡張子の付け方は最終フレームと同じにする。同じ実行の複数枚を検収側が同じ読み手で読めるようにするためである。
fn 後置きを足す(基準: &Path, 後置き: &str) -> PathBuf {
    let 名前 = 基準.file_name().map_or_else(|| "frame".to_string(), |名前| 名前.to_string_lossy().into_owned());
    基準.with_file_name(format!("{名前}{後置き}"))
}
