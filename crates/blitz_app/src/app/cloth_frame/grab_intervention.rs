//! 掴み操作を布の介入へ写す発行元。掴み中かどうかを1つ持ち、離した最初の実刻みで「離す」介入を1回だけ出す。
//!
//! 刻みを1本も進めない描画で介入を1つも作らないのは、「離す」が押した瞬間の操作と同じ一回きりの値だからである。
//! その描画で作ると、掴み中の記憶だけが戻って介入はGPUへ届かず、布は掴まれたまま二度と解放されない。
//! 掴む介入は押している間ずっと意味を持つ連続量であり、刻みを進める描画のたびにその時点の目標位置から作り直す。
//! 参照: `_doc/設計/時間の規律.md`「判断5」「入力の規律」。

use blitz_sim::介入;

use super::掴み粒子添字;
use crate::app::進める刻み数;

/// 掴み操作のエッジ検出と、その描画ぶんの介入一覧の発行。
pub(in crate::app) struct 掴み介入の発行 {
    掴み中だった: bool,
}

impl 掴み介入の発行 {
    pub(in crate::app) fn 掴んでいない状態から始める() -> Self {
        Self { 掴み中だった: false }
    }

    /// その描画でGPUへ渡す介入一覧を作る。目標位置が`None`なのは掴んでいない描画である。
    /// 刻みを1本も進めない描画では、掴み中の記憶を書き換えず空の一覧を返す。
    pub(in crate::app) fn この描画の介入一覧を作る(
        &mut self, 掴みの目標位置: Option<[f32; 3]>, 刻み数: 進める刻み数
    ) -> Vec<介入> {
        if 刻み数.一本も進めないか() {
            return Vec::new();
        }
        match 掴みの目標位置 {
            Some(目標位置) => {
                self.掴み中だった = true;
                vec![介入::掴む {
                    粒子添字: 掴み粒子添字,
                    目標位置,
                }]
            }
            None if self.掴み中だった => {
                self.掴み中だった = false;
                vec![介入::離す {
                    粒子添字: 掴み粒子添字
                }]
            }
            None => Vec::new(),
        }
    }
}
