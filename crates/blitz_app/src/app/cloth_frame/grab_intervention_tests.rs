//! 掴み操作の介入を刻みへ配る規律の検証。押した瞬間の操作と同じく、離すが刻み0本の描画で消えないことを見る。

use blitz_math::{メートル, ワールド, 位置};
use blitz_sim::constraint_graph::目標拘束添字;
use blitz_sim::介入;

use super::掴み介入の発行;
use crate::app::進める刻み数;

const 拘束添字: 目標拘束添字 = 目標拘束添字::生成する(32);

fn 目標位置() -> 位置<ワールド> {
    位置::生成する(メートル::生成する(1.0), メートル::生成する(2.0), メートル::生成する(3.0))
}

fn 掴んでいる発行元() -> 掴み介入の発行 {
    let mut 発行 = 掴み介入の発行::掴んでいない状態から始める();
    let 一覧 = 発行.この描画の介入一覧を作る(Some(目標位置()), 拘束添字, 進める刻み数::一つだけ進める());
    assert!(matches!(一覧.as_slice(), [介入::目標拘束を有効にする { 拘束添字: 添字, .. }] if *添字 == 拘束添字));
    発行
}

/// 反証: 刻み0本の描画でも介入を作ると、掴み中の記憶だけが戻って離すがGPUへ届かず、布が掴まれたまま戻らない。
#[test]
fn 離した描画の刻みが零本なら離す介入は次の実刻みまで持ち越される() {
    let mut 発行 = 掴んでいる発行元();
    assert!(発行.この描画の介入一覧を作る(None, 拘束添字, 進める刻み数::一つも進めない()).is_empty());
    let 一覧 = 発行.この描画の介入一覧を作る(None, 拘束添字, 進める刻み数::一つだけ進める());
    assert!(matches!(一覧.as_slice(), [介入::目標拘束を無効にする { 拘束添字: 添字 }] if *添字 == 拘束添字));
}

/// 反証: 離すを毎描画出すと、掴んでいない間ずっと介入が積まれる。出るのは離した最初の実刻みだけである。
#[test]
fn 離す介入は最初の実刻みだけに出る() {
    let mut 発行 = 掴んでいる発行元();
    assert!(matches!(
        発行.この描画の介入一覧を作る(None, 拘束添字, 進める刻み数::一つだけ進める()).as_slice(),
        [介入::目標拘束を無効にする { .. }]
    ));
    assert!(発行.この描画の介入一覧を作る(None, 拘束添字, 進める刻み数::一つだけ進める()).is_empty());
}

/// 反証: 刻み0本の描画で掴みを記録すると、掴んでいない状態へ戻ったときに離すが二重に出る。
#[test]
fn 刻み零本の描画は掴み中の記憶を書き換えない() {
    let mut 発行 = 掴み介入の発行::掴んでいない状態から始める();
    assert!(
        発行
            .この描画の介入一覧を作る(Some(目標位置()), 拘束添字, 進める刻み数::一つも進めない())
            .is_empty()
    );
    assert!(発行.この描画の介入一覧を作る(None, 拘束添字, 進める刻み数::一つだけ進める()).is_empty());
}
