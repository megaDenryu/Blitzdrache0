//! 可視判定と個体別LODの配線。束ごとの可視材料と個体別の段の記憶を保持し、毎フレーム視錐台を作って
//! 群ごとに描く個体の並びを決め、レンダラーが読むID列・段の範囲・選択の一覧へ写す。
//! 判定と選択の規則そのものはエンジン側の純ロジックが持ち、ここは材料の出し入れと呼び出しだけを行う。
//! 距離の刻みとヒステリシス幅は`settings`が持ち、束の出入りは`registry`、1フレーム分の走査は`frame_select`にある。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」「個体別LOD」

mod frame_select;
mod registration;
mod registry;
mod settings;
mod tray;

use blitz_engine::{個体LOD選択設定, 段選択方式, 視錐台};
use blitz_math::{クリップ, ワールド, 変換, 大域ワールド位置};
use blitz_render::描画束ID;

pub(crate) use registration::群可視材料の登録;
pub(super) use tray::可視選択受け皿;

use crate::error::起動エラー;

pub(super) struct 可視判定配線 {
    /// `--no-instance-cull`で偽にする。偽のときは視錐台で絞らず全個体を可視として扱う。
    /// 段の選択はこの切替と独立に働く。
    可視判定有効: bool,
    /// `--no-instance-lod`で偽にする。偽のときは全個体を最詳細段で描く。
    段選択有効: bool,
    設定: 個体LOD選択設定,
    台帳: registry::群可視材料台帳,
    受け皿: 可視選択受け皿,
}

impl 可視判定配線 {
    pub(super) fn 生成する(可視判定有効: bool, 段選択有効: bool) -> Self {
        Self {
            可視判定有効,
            段選択有効,
            設定: settings::段の閾値設定を作る(),
            台帳: registry::群可視材料台帳::default(),
            受け皿: 可視選択受け皿::生成する(),
        }
    }

    pub(super) fn 束を登録する(&mut self, 束id: 描画束ID, 登録一覧: Vec<群可視材料の登録>) {
        self.台帳.束を登録する(束id, 登録一覧);
    }

    pub(super) fn 束を解除する(&mut self, 束id: 描画束ID) {
        self.台帳.束を解除する(束id);
    }

    pub(super) fn 全束を解除する(&mut self) {
        self.台帳.全束を解除する();
    }

    /// カメラ更新の後、描画入力の組み立てより前に呼ぶ。視錐台はカメラ相対フレームのビュー射影から導く。
    pub(super) fn 判定する(
        &mut self, ビュー射影: 変換<ワールド, クリップ>, カメラ大域原点: 大域ワールド位置
    ) -> Result<(), 起動エラー> {
        self.受け皿.空にする();
        frame_select::一フレーム分を選ぶ(&mut frame_select::選択の条件 {
            視錐台: 視錐台::カメラ相対ビュー射影から生成する(ビュー射影),
            カメラ大域原点,
            可視判定有効: self.可視判定有効,
            段選択: if self.段選択有効 {
                段選択方式::距離とヒステリシス(self.設定)
            } else {
                段選択方式::最詳細に固定
            },
            台帳: &mut self.台帳,
            受け皿: &mut self.受け皿,
        })
    }

    /// 起動から現在までに個体の段が入れ替わった延べ回数。ヒステリシス帯の内側での往復で段が振動していないことを、
    /// 実行の外からこの数で見る。
    pub(super) fn 段切替回数(&self) -> u64 {
        self.台帳.段切替回数()
    }

    /// 現在登録されている群の件数。束の追加で材料と段の記憶が生まれ、解除で漏れなく消えることを、実行の外からこの数で見る。
    pub(super) fn 登録数(&self) -> usize {
        self.台帳.登録数()
    }

    /// 描画入力へ借用で渡す間だけ受け皿を呼び出し元へ預ける。確保した容量を次のフレームへ持ち越すため、同じフレームのうちに返す。
    /// 注意: 預けている間の受け皿は空である。この型へ選択を読む処理を足すときは、預ける前か返した後に読む。
    pub(super) fn 受け皿を預ける(&mut self) -> 可視選択受け皿 {
        std::mem::take(&mut self.受け皿)
    }

    pub(super) fn 受け皿を戻す(&mut self, 受け皿: 可視選択受け皿) {
        self.受け皿 = 受け皿;
    }
}
