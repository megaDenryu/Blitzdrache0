//! 可視判定の配線。束ごとの可視材料を保持し、毎フレーム視錐台を作って群ごとに可視個体を選び、
//! レンダラーが読む可視ID列と選択の一覧へ写す。判定の規則そのものはエンジン側の純ロジックが持ち、
//! ここは材料の出し入れと呼び出しだけを行う。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」

mod registration;
mod tray;

use blitz_engine::{可視個体を選ぶ, 視錐台};
use blitz_math::{クリップ, ワールド, 変換, 大域ワールド位置};
use blitz_render::{可視個体選択, 描画束ID};

pub(crate) use registration::群可視材料の登録;
pub(super) use tray::可視選択受け皿;

use crate::error::起動エラー;

pub(super) struct 可視判定配線 {
    /// `--no-instance-cull`で偽にする。偽のときは選択を1件も出さないため、レンダラーは全対象の全個体を描く。
    有効: bool,
    材料一覧: Vec<(描画束ID, 群可視材料の登録)>,
    受け皿: 可視選択受け皿,
}

impl 可視判定配線 {
    pub(super) fn 生成する(有効: bool) -> Self {
        Self {
            有効,
            材料一覧: Vec::new(),
            受け皿: 可視選択受け皿::生成する(),
        }
    }

    /// 描画束をレンダラーへ追加した直後に呼ぶ。束が持たない群は登録が0件になり、その束の対象は全個体を描く。
    pub(super) fn 束を登録する(&mut self, 束id: 描画束ID, 登録一覧: Vec<群可視材料の登録>) {
        self.束を解除する(束id);
        self.材料一覧.extend(登録一覧.into_iter().map(|登録| (束id, 登録)));
    }

    /// 描画束の解除を予約した時点で呼ぶ。レンダラーがその束を描かなくなった後も材料が残ると、
    /// 存在しない束の選択を毎フレーム作り続ける。
    pub(super) fn 束を解除する(&mut self, 束id: 描画束ID) {
        self.材料一覧.retain(|(登録済みid, _)| *登録済みid != 束id);
    }

    /// シーン差し替えは全束を作り直すため、材料も全部捨てる。
    pub(super) fn 全束を解除する(&mut self) {
        self.材料一覧.clear();
    }

    /// カメラ更新の後、描画入力の組み立てより前に呼ぶ。視錐台はカメラ相対フレームのビュー射影から導く。
    pub(super) fn 判定する(
        &mut self, ビュー射影: 変換<ワールド, クリップ>, カメラ大域原点: 大域ワールド位置
    ) -> Result<(), 起動エラー> {
        self.受け皿.空にする();
        if !self.有効 {
            return Ok(());
        }
        let 視錐台 = 視錐台::カメラ相対ビュー射影から生成する(ビュー射影);
        for (束id, 登録) in &self.材料一覧 {
            // アンカーをカメラ相対へ狭める境界はレンダラーの描画対象と同じであり、失敗する条件も同じである。
            // 同じ破れを2つの型で表さないため、描画側の型付きエラーで表す。
            let アンカー = 登録
                .大域アンカー()
                .カメラ相対へ変換する(カメラ大域原点)
                .map_err(blitz_render::レンダラーエラー::カメラ相対変換失敗)?;
            let 開始 = self.受け皿.id列の長さ();
            let 計数 = 可視個体を選ぶ(&視錐台, 登録.材料(), アンカー, self.受け皿.id列を借りる());
            self.受け皿
                .選択を積む(可視個体選択::生成する(*束id, 登録.対象添字(), 開始, 計数.可視数()));
        }
        Ok(())
    }

    /// 描画入力へ借用で渡す間だけ受け皿を呼び出し元へ預ける。確保した容量を次のフレームへ持ち越すため、同じフレームのうちに返す。
    /// 注意: 預けている間の受け皿は空である。この型へ選択を読む処理を足すときは、預ける前か返した後に読む。
    pub(super) fn 受け皿を預ける(&mut self) -> 可視選択受け皿 {
        std::mem::take(&mut self.受け皿)
    }

    pub(super) fn 受け皿を戻す(&mut self, 受け皿: 可視選択受け皿) {
        self.受け皿 = 受け皿;
    }
}
