//! ゲーム操作に割り当てたキーの押下状態を所有する。触れるのはこの9つの操作の真偽だけであり、カメラ操作のキーとは重ならない。
//!
//! 移動を方向キーへ割り当てるのは、WASDとQEをカメラ操作が既に使っているためである。同じキーを2つの意味へ割り当てると、
//! ゲームを遊ぶ起動で視点を回すだけでプレイヤーが歩く。
//!
//! 決定と取り消しとジャンプは押し下げが届いたことを旗で覚えてから渡す。押しっぱなしの間ずっと決定が届くと、タイトルから終了確認まで
//! 数フレームで流れてしまうためである。旗で覚えるのは、1フレームの間に押して離してまた押した操作を取りこぼさないためであり、
//! 前のフレームの押下と比べる形にすると、この短い押下が押しっぱなしと見分けられなくなる。
//! 決定はEnterだけであり、Spaceはジャンプに割り当てる。同じ鍵ではタイトル画面でジャンプの操作を押すと同時に開始してしまう(判断8)。
//! 走るは左Shiftの押下が続く間ずっと真である。カメラの系統の切替(F4)も押し下げの旗で持つ。F3は開発用UIの切替が使っている。

use winit::keyboard::KeyCode;

use blitz_game::確定済みの操作入力;

/// ゲーム操作に割り当てたキーの押下状態。移動と走るは押下の継続、決定と取り消しとジャンプは押し下げが届いた旗で持つ。
#[derive(Debug, Default)]
pub(super) struct ゲーム操作のキー状態 {
    前へ進むキー押下中: bool,
    後ろへ下がるキー押下中: bool,
    左へ寄るキー押下中: bool,
    右へ寄るキー押下中: bool,
    走るキー押下中: bool,
    決定キー押下中: bool,
    決定キーを押し下げた: bool,
    取り消しキー押下中: bool,
    取り消しキーを押し下げた: bool,
    ジャンプキー押下中: bool,
    ジャンプキーを押し下げた: bool,
    カメラの系統の切替キー押下中: bool,
    カメラの系統の切替キーを押し下げた: bool,
}

impl ゲーム操作のキー状態 {
    /// カメラ操作が読まなかったキーコードだけがここへ来る。割り当ての無いキーは読み飛ばす。
    pub(super) fn キーコードを反映する(&mut self, コード: KeyCode, 押下中: bool) {
        match コード {
            KeyCode::ArrowUp => self.前へ進むキー押下中 = 押下中,
            KeyCode::ArrowDown => self.後ろへ下がるキー押下中 = 押下中,
            KeyCode::ArrowLeft => self.左へ寄るキー押下中 = 押下中,
            KeyCode::ArrowRight => self.右へ寄るキー押下中 = 押下中,
            KeyCode::ShiftLeft => self.走るキー押下中 = 押下中,
            KeyCode::Enter => {
                self.決定キーを押し下げた |= 押下中 && !self.決定キー押下中;
                self.決定キー押下中 = 押下中;
            }
            KeyCode::Escape => {
                self.取り消しキーを押し下げた |= 押下中 && !self.取り消しキー押下中;
                self.取り消しキー押下中 = 押下中;
            }
            KeyCode::Space => {
                self.ジャンプキーを押し下げた |= 押下中 && !self.ジャンプキー押下中;
                self.ジャンプキー押下中 = 押下中;
            }
            KeyCode::F4 => {
                self.カメラの系統の切替キーを押し下げた |= 押下中 && !self.カメラの系統の切替キー押下中;
                self.カメラの系統の切替キー押下中 = 押下中;
            }
            _ => {}
        }
    }

    /// このフレームぶんの操作入力を確定する。押し下げの旗はここで消費する。
    pub(super) fn 確定する(&mut self) -> 確定済みの操作入力 {
        let 入力 = 確定済みの操作入力 {
            前へ進む操作を押しているか: self.前へ進むキー押下中,
            後ろへ下がる操作を押しているか: self.後ろへ下がるキー押下中,
            左へ寄る操作を押しているか: self.左へ寄るキー押下中,
            右へ寄る操作を押しているか: self.右へ寄るキー押下中,
            走る操作を押しているか: self.走るキー押下中,
            決定操作を押した瞬間か: self.決定キーを押し下げた,
            取り消し操作を押した瞬間か: self.取り消しキーを押し下げた,
            ジャンプ操作を押した瞬間か: self.ジャンプキーを押し下げた,
            カメラの系統を切り替える操作を押した瞬間か: self.カメラの系統の切替キーを押し下げた,
        };
        self.決定キーを押し下げた = false;
        self.取り消しキーを押し下げた = false;
        self.ジャンプキーを押し下げた = false;
        self.カメラの系統の切替キーを押し下げた = false;
        入力
    }
}
