//! ゲーム操作のキーの確定と、適用方針の遮断の検証。カメラ操作のキーがゲーム操作へ漏れないことも見る。

use winit::keyboard::KeyCode;

use super::game_key_state::ゲーム操作のキー状態;
use super::ゲーム操作の適用方針;
use crate::cli::起動モード;
use blitz_game::{ゲームインテント, 操作軸の倒し量, 確定済みの操作入力};

#[test]
fn 方向キーは押している間ずっと真になる() {
    let mut キー状態 = ゲーム操作のキー状態::default();
    キー状態.キーコードを反映する(KeyCode::ArrowUp, true);
    assert!(キー状態.確定する().前へ進む操作を押しているか);
    assert!(キー状態.確定する().前へ進む操作を押しているか);
}

/// 反証: 決定を押下の継続で渡すと、押しっぱなしの1秒でタイトルから終了確認まで流れる。
#[test]
fn 決定は押し始めたフレームだけ真になる() {
    let mut キー状態 = ゲーム操作のキー状態::default();
    キー状態.キーコードを反映する(KeyCode::Enter, true);
    assert!(キー状態.確定する().決定操作を押した瞬間か);
    assert!(!キー状態.確定する().決定操作を押した瞬間か);
    キー状態.キーコードを反映する(KeyCode::Enter, false);
    キー状態.キーコードを反映する(KeyCode::Enter, true);
    assert!(キー状態.確定する().決定操作を押した瞬間か);
}

/// 反証: 前のフレームの押下と比べる形では、1フレームの間に押して離した短い操作が押しっぱなしと区別できず消える。
#[test]
fn 同じフレームに押して離した決定も届く() {
    let mut キー状態 = ゲーム操作のキー状態::default();
    キー状態.キーコードを反映する(KeyCode::Enter, true);
    キー状態.キーコードを反映する(KeyCode::Enter, false);
    assert!(キー状態.確定する().決定操作を押した瞬間か);
    assert!(!キー状態.確定する().決定操作を押した瞬間か);
}

