//! ゲーム操作の入力をそのフレームへ適用するかどうかの方針。担当するのは「実行の種類から方針を1つ決める」ことと
//! 「写像したゲームインテントを、方針に従って通すか無操作へ落とすか」だけである。ゲームの状態も入力の中身も知らない。
//!
//! カメラ操作の適用方針(`camera_intent_policy.rs`)の規律をそのまま継承する。フレーム数の決まった実行はどれも
//! 成果物の決定性を前提にしており、そこへ実ウィンドウ由来のゲーム操作が入ると、同じ引数の起動が別の進行段階で終わる。
//! ゲームの進行段階はプレイヤーの位置を通じてカメラとストリーミングの導出元になるため、揺れが絵まで届く。
//!
//! 押下の蓄積そのものは方針より先に消費してある。消費を止めると届いた入力が溜まり続け、方針を変えた瞬間に一気に流れる。

use blitz_game::ゲームインテント;

use crate::cli::起動モード;

/// ゲーム操作の入力を適用するかどうか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum ゲーム操作の適用方針 {
    対話入力を適用する,   // 無期限実行。方向キー・決定・取り消しをそのフレームのゲーム更新へ適用する
    ゲーム操作を通さない, // フレーム数の決まった実行。届いた入力を蓄積から消費したうえで、ゲームの進行段階を1度も動かさない
}

impl ゲーム操作の適用方針 {
    /// フレーム数の決まった実行(スモーク・ベンチ・段差走査)はゲーム操作を通さず、無期限実行は対話入力を適用する。
    pub(crate) fn 起動モードから決める(モード: 起動モード) -> Self {
        match モード {
            起動モード::無期限実行 => Self::対話入力を適用する,
            起動モード::スモーク実行 { .. } | 起動モード::ベンチ実行 { .. } | 起動モード::段差走査実行 { .. } => {
                Self::ゲーム操作を通さない
            }
        }
    }

    /// カメラの系統の切替の操作を方針に通す。通さない側では押していないことにする。フレーム数の決まった実行が常に
    /// プレイヤー用の系統で走り、検収の絵が実行のたびに一致するためである(判断9)。
    pub(crate) fn カメラの系統の切替を通す(self, 押した瞬間か: bool) -> bool {
        match self {
            Self::対話入力を適用する => 押した瞬間か,
            Self::ゲーム操作を通さない => false,
        }
    }

    /// 写像したインテントを方針に通す。通さない側では無操作のインテントへ落とす。
    pub(crate) fn 通す(self, 写像したインテント: ゲームインテント) -> ゲームインテント {
        match self {
            Self::対話入力を適用する => 写像したインテント,
            Self::ゲーム操作を通さない => ゲームインテント::無操作(),
        }
    }
}
