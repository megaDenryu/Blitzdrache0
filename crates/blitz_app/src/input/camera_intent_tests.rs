//! カメラ操作の適用方針が、実行の種類ごとに入力をどう扱うかを固定する。
//!
//! 2つの実行を対にするのは、片方だけでは「常に適用する」実装も「常に落とす」実装も通ってしまうためである。
//! 無期限実行で動くことと、フレーム数の決まった実行で動かないことの両方が要る。
//!
//! 蓄積が消費されることを別に見るのは、固定姿勢で消費を止めると届いた入力が溜まり続けるためである。
//! 溜まった状態は、同じ実装を無期限実行で使ったときに最初のフレームでカメラを飛ばす。

use super::{カメラ操作の適用方針, 入力状態};
use crate::cli::起動モード;

/// ドラッグとホイールを蓄積した状態を作る。取り込みの経路(winitイベント)を通さないのは、この検査の対象が
/// 蓄積からインテントを作る段だからである。
fn 蓄積を持つ入力状態(方針: カメラ操作の適用方針) -> 入力状態 {
    let mut 状態 = 入力状態::生成する(方針);
    状態.ドラッグ蓄積 = (10.0, -6.0);
    状態.ホイール蓄積 = 2.0;
    状態
}

fn 静止しているか(インテント: &blitz_engine::カメラインテント) -> bool {
    インテント.ヨー差分.値() == 0.0 && インテント.ピッチ差分.値() == 0.0 && インテント.距離倍率 == 1.0
}

#[test]
fn 無期限実行は起動モードから対話入力の適用を選ぶ() {
    assert_eq!(
        カメラ操作の適用方針::起動モードから決める(起動モード::無期限実行),
        カメラ操作の適用方針::対話入力を適用する
    );
}

#[test]
fn フレーム数の決まった実行は起動モードから固定姿勢を選ぶ() {
    for モード in [起動モード::スモーク実行 { フレーム数: 12 }, 起動モード::ベンチ実行 { フレーム数: 12 }] {
        assert_eq!(カメラ操作の適用方針::起動モードから決める(モード), カメラ操作の適用方針::固定姿勢を保つ);
    }
}

#[test]
fn 対話入力を適用する実行では蓄積がインテントへ出る() {
    let mut 状態 = 蓄積を持つ入力状態(カメラ操作の適用方針::対話入力を適用する);
    assert!(!静止しているか(&状態.インテントを確定する()));
}

#[test]
fn 固定姿勢の実行では蓄積があってもインテントが静止する() {
    let mut 状態 = 蓄積を持つ入力状態(カメラ操作の適用方針::固定姿勢を保つ);
    assert!(静止しているか(&状態.インテントを確定する()));
}

/// 固定姿勢でも蓄積は消費される。消費されなければ2フレーム目に持ち越され、方針を変えた実装で飛ぶ。
#[test]
fn 固定姿勢でも蓄積は消費される() {
    let mut 状態 = 蓄積を持つ入力状態(カメラ操作の適用方針::固定姿勢を保つ);
    状態.インテントを確定する();
    assert_eq!(状態.ドラッグ蓄積, (0.0, 0.0));
    assert_eq!(状態.ホイール蓄積, 0.0);
}
