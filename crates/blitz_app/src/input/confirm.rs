//! 蓄積した入力状態からこのフレームぶんのカメラインテントを確定する。

use blitz_engine::カメラインテント;
use blitz_math::ラジアン;

use super::入力状態;

const ドラッグ感度: f32 = 0.005;
const キー角速度: f32 = 0.02;
/// ホイールの一刻みが距離へ掛ける比率。手前へ一刻みで1/1.1倍、奥へ一刻みで1.1倍になる。
/// 蓄積へ比率のべき乗で効かせるのは、1フレームに複数の刻みが届いても倍率が0へ落ちないためである。
/// 蓄積へ感度を掛けて1から引く線形の式では、蓄積10で倍率がちょうど0になり、急に回した1フレームで距離が最小へ張り付く。
const ホイールの一刻みが距離へ掛ける比率: f32 = 1.1;
/// 距離キーを押している一フレームが距離へ掛ける比率。毎秒60フレームで約3.28倍(奥へ)と約1/3.28倍(手前へ)になる。
/// 押している間ずっと画面を見ながら加減できる操作であるため、従来の一フレーム1.02倍という速さをそのまま残し、形だけをホイールと同じ指数へ揃えた。
const 距離キーの一フレームが距離へ掛ける比率: f32 = 1.02;

pub(super) fn 確定する(状態: &mut 入力状態) -> カメラインテント {
    let ヨーキー方向 = 符号(状態.d押下中, 状態.a押下中);
    let ピッチキー方向 = 符号(状態.w押下中, 状態.s押下中);
    let 距離キー方向 = 符号(状態.e押下中, 状態.q押下中);

    let ヨー差分 = 状態.ドラッグ蓄積.0 * ドラッグ感度 + ヨーキー方向 * キー角速度;
    let ピッチ差分 = 状態.ドラッグ蓄積.1 * ドラッグ感度 + ピッチキー方向 * キー角速度;
    let 距離倍率 = ホイールの一刻みが距離へ掛ける比率.powf(-状態.ホイール蓄積) * 距離キーの一フレームが距離へ掛ける比率.powf(-距離キー方向);

    状態.ドラッグ蓄積 = (0.0, 0.0);
    状態.ホイール蓄積 = 0.0;

    カメラインテント {
        ヨー差分: ラジアン::生成する(ヨー差分),
        ピッチ差分: ラジアン::生成する(ピッチ差分),
        距離倍率,
    }
}

/// 正方向キーが押されていれば+1、負方向キーのみが押されていれば-1、それ以外は0。
fn 符号(正方向押下中: bool, 負方向押下中: bool) -> f32 {
    match (正方向押下中, 負方向押下中) {
        (true, false) => 1.0,
        (false, true) => -1.0,
        _ => 0.0,
    }
}
