//! ホイールと距離キーが1フレームで距離へ掛ける比率の契約と、操作を続けたときに距離が上下限の内側へ留まること。
//!
//! 比率の設計値をこの検査へ書き写すのは、値そのものが操作の速さだからである。実装の定数を変えたらここが落ち、
//! 速さを変えたことが検査の書き換えとして残る。
//!
//! 1フレームに複数の刻みが届く場合を別に見るのは、そこが実機で壊れた形だからである。蓄積へ感度を掛けて1から引く
//! 線形の式は蓄積10で倍率がちょうど0になり、マウスを急に回した1フレームで距離が最小へ張り付く。

use super::{カメラ操作の適用方針, 入力状態};

/// ホイールの一刻みが距離へ掛ける比率の設計値。
const 一刻みの距離比率: f32 = 1.1;
/// 距離キーを押している一フレームが距離へ掛ける比率の設計値。
const キーの一フレームの距離比率: f32 = 1.02;
/// 比率の比較に許す相対の差。f32のべき乗の丸めを通すだけの幅である。
const 比率の許容相対差: f32 = 1e-5;

fn ホイールを回した状態(刻み数: f32) -> 入力状態 {
    let mut 状態 = 入力状態::生成する(カメラ操作の適用方針::対話入力を適用する);
    状態.ホイール蓄積 = 刻み数;
    状態
}

fn 距離倍率(状態: &mut 入力状態) -> f32 {
    状態.インテントを確定する().距離倍率
}

fn ほぼ等しいか(実測: f32, 期待: f32) -> bool {
    (実測 - 期待).abs() <= 期待.abs() * 比率の許容相対差
}

#[test]
fn ホイールの一刻みは距離へ設計どおりの比率を掛ける() {
    let 手前へ一刻み = 距離倍率(&mut ホイールを回した状態(1.0));
    let 奥へ一刻み = 距離倍率(&mut ホイールを回した状態(-1.0));
    assert!(ほぼ等しいか(手前へ一刻み, 1.0 / 一刻みの距離比率), "手前へ一刻みの倍率: {手前へ一刻み}");
    assert!(ほぼ等しいか(奥へ一刻み, 一刻みの距離比率), "奥へ一刻みの倍率: {奥へ一刻み}");
}

/// 蓄積10は線形の式で倍率をちょうど0にしていた蓄積である。指数の形では比率の10乗になり、0にならない。
#[test]
fn 一フレームに十刻み届いても距離倍率は比率の十乗になる() {
    let 十刻み = 距離倍率(&mut ホイールを回した状態(10.0));
    assert!(ほぼ等しいか(十刻み, 1.0 / 一刻みの距離比率.powi(10)), "十刻みの倍率: {十刻み}");
    assert!(十刻み > 0.0, "十刻みで距離倍率が正でなくなった: {十刻み}");
}

#[test]
fn 距離キーは一フレームごとに設計どおりの比率を掛ける() {
    let mut 手前へ = 入力状態::生成する(カメラ操作の適用方針::対話入力を適用する);
    手前へ.e押下中 = true;
    let mut 奥へ = 入力状態::生成する(カメラ操作の適用方針::対話入力を適用する);
    奥へ.q押下中 = true;
    let 手前への倍率 = 距離倍率(&mut 手前へ);
    let 奥への倍率 = 距離倍率(&mut 奥へ);
    assert!(
        ほぼ等しいか(手前への倍率, 1.0 / キーの一フレームの距離比率),
        "手前への倍率: {手前への倍率}"
    );
    assert!(ほぼ等しいか(奥への倍率, キーの一フレームの距離比率), "奥への倍率: {奥への倍率}");
}

/// 既定のカメラはヨー0・ピッチ0・注視点が原点であるため、視点のz成分がそのまま距離になる。
fn 既定カメラの距離(カメラ: &blitz_engine::カメラ) -> f32 {
    カメラ.視点ワールド位置().z().値()
}

#[test]
fn ホイールを奥へ回し続けても距離は遠クリップの内側に留まる() {
    let mut カメラ = blitz_engine::カメラ::生成する();
    for _ in 0..100 {
        カメラ.更新する(ホイールを回した状態(-50.0).インテントを確定する());
    }
    let 距離 = 既定カメラの距離(&カメラ);
    assert!(距離.is_finite(), "距離が有限でなくなった: {距離}");
    assert!(距離 <= カメラ.遠クリップ().値(), "距離が遠クリップを超えた: {距離}");
}

#[test]
fn ホイールを手前へ回し続けても距離は正のまま残る() {
    let mut カメラ = blitz_engine::カメラ::生成する();
    for _ in 0..100 {
        カメラ.更新する(ホイールを回した状態(50.0).インテントを確定する());
    }
    let 距離 = 既定カメラの距離(&カメラ);
    assert!(距離 > 0.0, "距離が正でなくなった: {距離}");
}
