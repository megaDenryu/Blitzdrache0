//! カメラ操作の入力をそのフレームへ適用するかどうかの方針。担当するのは「実行の種類から方針を1つ決める」ことと
//! 「蓄積から作ったインテントを、方針に従って通すか静止へ落とすか」だけである。カメラの姿勢も入力の中身も知らない。
//!
//! フレーム数の決まった実行で入力を適用しないのは、その実行がどれも成果物の決定性を前提にしているためである。
//! `--frames`の実行も実ウィンドウを作るため、そのウィンドウへ届いた入力イベントが毎フレームカメラへ入る。
//! 入力が届くかどうかはポインタの位置・フォーカス・OSのイベント配送で変わり、同じ引数の起動が別の構図の絵を返す。
//! 2026-08-05の実測では、同じ引数の60回の起動のうち2回、板の位置と大きさが違う絵が出た(板の並びが画面中央から
//! 約3.4パーセント広がり、上段が約9パーセント縮んで下段が約5パーセント伸びた)。
//!
//! **止めるのは実ウィンドウから届くカメラ操作だけである。** リサイズ・最小化と復帰・終了はウィンドウの
//! ライフサイクルであり、この方針を1つも通らない。検収が自ら与える決定的なカメラ変更(個体詳細段の探査・
//! 起動指定の平行移動と俯角と方位)も、蓄積を経ずにカメラを直に動かすためこの方針の外にある。
//!
//! 経過秒の供給元(`app/time_of_day/exposure_elapsed.rs`)と同じ構造にしてあるのは、どちらも
//! 「実時間や実環境に依る値を、実行の種類で1度だけ選び分ける」同じ形の判断だからである。

use blitz_engine::カメラインテント;
use blitz_math::ラジアン;

use crate::cli::起動モード;

/// カメラ操作の入力を適用するかどうか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum カメラ操作の適用方針 {
    /// 無期限実行。ドラッグ・ホイール・移動キーをそのフレームのカメラへ適用する。
    対話入力を適用する,
    /// フレーム数の決まった実行。届いた入力を蓄積から消費したうえで、カメラを1度も動かさない。
    固定姿勢を保つ,
}

impl カメラ操作の適用方針 {
    /// フレーム数の決まった実行(スモーク・ベンチ・段差走査)は固定姿勢、無期限実行は対話入力を適用する。
    pub(crate) fn 起動モードから決める(モード: 起動モード) -> Self {
        match モード {
            起動モード::無期限実行 => Self::対話入力を適用する,
            起動モード::スモーク実行 { .. } | 起動モード::ベンチ実行 { .. } | 起動モード::段差走査実行 { .. } => {
                Self::固定姿勢を保つ
            }
        }
    }

    /// 蓄積から作ったインテントを方針に通す。固定姿勢では静止のインテントへ落とす。
    ///
    /// 落とす側でも蓄積の消費そのものは呼び出し元が済ませてある。消費を止めると、届いた入力が溜まり続け、
    /// 方針を変えた瞬間にカメラが飛ぶ。
    pub(super) fn 通す(self, 蓄積から作ったインテント: カメラインテント) -> カメラインテント {
        match self {
            Self::対話入力を適用する => 蓄積から作ったインテント,
            Self::固定姿勢を保つ => 静止のインテント(),
        }
    }
}

/// カメラを1つも動かさないインテント。角の差分は0、距離の倍率は1である。
fn 静止のインテント() -> カメラインテント {
    カメラインテント {
        ヨー差分: ラジアン::生成する(0.0),
        ピッチ差分: ラジアン::生成する(0.0),
        距離倍率: 1.0,
    }
}
