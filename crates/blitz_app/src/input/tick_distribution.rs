//! 1描画で確定した操作入力を、その描画で進める固定刻みへ順に配る型。担当するのは「押した瞬間の操作を最初の刻みだけへ渡し、
//! 押下が続く操作を全ての刻みへ渡す」ことだけであり、刻みを何本進めるかも、操作が何を意味するかも知らない。
//!
//! 押した瞬間の操作(決定・取り消し)を全ての刻みへ同じ値で配ると、1回の押し下げが刻みの本数だけ発火する。
//! 処理落ちで刻みが4本になった描画ほど、タイトルから終了確認まで速く流れることになる。押下が続く操作は、
//! その描画のあいだ押し続けているのが実際の押し方であるため全ての刻みへ配る。カメラのヨーも同じ理由で全ての刻みへ配る。
//!
//! 配り終えたかを型が覚えるのは、呼び出し側が刻みの添字を比べる形にすると、繰り返しを書き換えたときに
//! 最初の1回という規律が静かに壊れるためである。
//! 参照: `_doc/設計/時間の規律.md`「入力の規律」。

use blitz_game::確定済みの操作入力;

/// 1描画ぶんの確定した操作入力を、刻みごとの値として順に取り出す器。
pub(crate) struct 刻みごとの操作入力 {
    確定した入力: 確定済みの操作入力,
    押した瞬間の操作をまだ配っていない: bool,
}

impl 刻みごとの操作入力 {
    pub(crate) fn 一描画の確定から生成する(確定した入力: 確定済みの操作入力) -> Self {
        Self {
            確定した入力,
            押した瞬間の操作をまだ配っていない: true,
        }
    }

    /// 次の1刻みへ渡す入力を取り出す。押した瞬間の操作は最初の1回だけ真のまま通り、2本目からは落ちる。
    pub(crate) fn 次の刻みぶんを取り出す(&mut self) -> 確定済みの操作入力 {
        if self.押した瞬間の操作をまだ配っていない {
            self.押した瞬間の操作をまだ配っていない = false;
            return self.確定した入力;
        }
        self.確定した入力.押した瞬間の操作を落とした入力()
    }
}
