//! 1描画の操作入力を確定する呼び出しと、その描画で進める刻み数の関係の検証。
//!
//! 配りの器を直に作る検証(`tick_distribution_tests`)では、確定が押し下げの旗を消費する順序を1つも見られない。
//! ここは押し下げを`入力状態`へ届けたところから始め、刻み0本の描画を挟んでも押した瞬間の操作が
//! 最初の実刻みへちょうど1回だけ届くことを見る。
//! 参照: `_doc/設計/時間の規律.md`「入力の規律」。

use winit::keyboard::KeyCode;

use super::{カメラ操作の適用方針, 入力状態};
use crate::app::進める刻み数;
use crate::cli::{起動モード, 遊ぶゲームの指定};
use crate::game::ゲーム配線;

fn 決定を押した入力状態() -> 入力状態 {
    let mut 状態 = 入力状態::生成する(カメラ操作の適用方針::起動モードから決める(起動モード::無期限実行));
    状態.ゲーム操作のキー.キーコードを反映する(KeyCode::Enter, true);
    状態
}

fn 遊ぶ配線() -> ゲーム配線 {
    ゲーム配線::起動設定から作る(遊ぶゲームの指定::歩くだけ, 起動モード::無期限実行)
}

/// 反証: 刻み0本の描画でも入力を確定すると、押し下げの旗がそこで消えて押した瞬間の操作が刻みへ1度も届かない。
#[test]
fn 刻み零本の描画を挟んでも押した瞬間の操作は最初の実刻みへ一度だけ届く() {
    let mut 状態 = 決定を押した入力状態();
    let mut 配線 = 遊ぶ配線();
    assert!(
        配線
            .この描画で進める刻みへ配る操作入力を確定する(&mut 状態, 進める刻み数::一つも進めない())
            .is_none()
    );
    let mut 配り = 配線
        .この描画で進める刻みへ配る操作入力を確定する(&mut 状態, 進める刻み数::一つだけ進める())
        .unwrap_or_else(|| panic!("遊ぶ起動で刻み1本の描画が配りの器を返さなかった"));
    assert!(配り.次の刻みぶんを取り出す().決定操作を押した瞬間か);
    assert!(!配り.次の刻みぶんを取り出す().決定操作を押した瞬間か);
}

/// 反証: 刻み0本の描画で旗を消すと、押し下げが2つの描画にまたがって二重に届くことも起こりうる。
/// 保持は次の実刻みまでであり、届いた後の描画には残らない。
#[test]
fn 一度届いた押した瞬間の操作は次の描画へ残らない() {
    let mut 状態 = 決定を押した入力状態();
    let mut 配線 = 遊ぶ配線();
    let mut 一描画目 = 配線
        .この描画で進める刻みへ配る操作入力を確定する(&mut 状態, 進める刻み数::一つだけ進める())
        .unwrap_or_else(|| panic!("遊ぶ起動で刻み1本の描画が配りの器を返さなかった"));
    assert!(一描画目.次の刻みぶんを取り出す().決定操作を押した瞬間か);
    let mut 二描画目 = 配線
        .この描画で進める刻みへ配る操作入力を確定する(&mut 状態, 進める刻み数::一つだけ進める())
        .unwrap_or_else(|| panic!("遊ぶ起動で刻み1本の描画が配りの器を返さなかった"));
    assert!(!二描画目.次の刻みぶんを取り出す().決定操作を押した瞬間か);
}

/// 反証: 遊ばない起動で操作を確定すると、`--game`の指定が無い実行が入力状態を書き換える。
#[test]
fn 遊ばない起動は刻みが有っても配りの器を作らない() {
    let mut 状態 = 決定を押した入力状態();
    let mut 配線 = ゲーム配線::起動設定から作る(遊ぶゲームの指定::ゲームを遊ばない, 起動モード::無期限実行);
    assert!(
        配線
            .この描画で進める刻みへ配る操作入力を確定する(&mut 状態, 進める刻み数::一つだけ進める())
            .is_none()
    );
}
