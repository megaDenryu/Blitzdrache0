//! 1描画の操作入力を刻みへ配る規律の検証。押した瞬間の操作と押下が続く操作で配り方が分かれることを見る。

use super::tick_distribution::刻みごとの操作入力;
use blitz_game::確定済みの操作入力;

fn 前へ進みながら決定を押した入力() -> 確定済みの操作入力 {
    確定済みの操作入力 {
        前へ進む操作を押しているか: true,
        決定操作を押した瞬間か: true,
        ..確定済みの操作入力::無操作()
    }
}

/// 反証: 押した瞬間の操作を全ての刻みへ配ると、処理落ちで刻みが増えた描画ほど決定が速く連打される。
#[test]
fn 押した瞬間の操作は最初の刻みだけへ配られる() {
    let mut 配り = 刻みごとの操作入力::一描画の確定から生成する(前へ進みながら決定を押した入力());
    assert!(配り.次の刻みぶんを取り出す().決定操作を押した瞬間か);
    for _ in 0..3 {
        assert!(!配り.次の刻みぶんを取り出す().決定操作を押した瞬間か);
    }
}

/// 反証: 押下が続く操作を最初の刻みだけへ配ると、刻みが4本進んだ描画でも1本ぶんしか歩かず、移動が実時間より遅れる。
#[test]
fn 押下が続く操作は全ての刻みへ配られる() {
    let mut 配り = 刻みごとの操作入力::一描画の確定から生成する(前へ進みながら決定を押した入力());
    for _ in 0..4 {
        assert!(配り.次の刻みぶんを取り出す().前へ進む操作を押しているか);
    }
}

#[test]
fn 取り消しも押した瞬間の操作として最初の刻みだけへ配られる() {
    let 押した = 確定済みの操作入力 {
        取り消し操作を押した瞬間か: true,
        ..確定済みの操作入力::無操作()
    };
    let mut 配り = 刻みごとの操作入力::一描画の確定から生成する(押した);
    assert!(配り.次の刻みぶんを取り出す().取り消し操作を押した瞬間か);
    assert_eq!(配り.次の刻みぶんを取り出す(), 確定済みの操作入力::無操作());
}

// 反証: ジャンプを全ての刻みへ配ると、1回の押し下げで刻みの本数だけ跳び直す。走るは押下が続く操作であり全ての刻みへ届く。
#[test]
fn ジャンプは最初の刻みだけへ配られ走るは全ての刻みへ配られる() {
    let 押した = 確定済みの操作入力 {
        ジャンプ操作を押した瞬間か: true,
        走る操作を押しているか: true,
        ..確定済みの操作入力::無操作()
    };
    let mut 配り = 刻みごとの操作入力::一描画の確定から生成する(押した);
    let 最初 = 配り.次の刻みぶんを取り出す();
    assert!(最初.ジャンプ操作を押した瞬間か && 最初.走る操作を押しているか);
    let 二本目 = 配り.次の刻みぶんを取り出す();
    assert!(!二本目.ジャンプ操作を押した瞬間か && 二本目.走る操作を押しているか);
}
