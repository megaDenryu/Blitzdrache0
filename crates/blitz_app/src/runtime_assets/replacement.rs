//! 置き場の中で生成物1つを別の生成物で上書きする局面。呼ばれるのはホットリロードの検収が書き換えを求めた
//! フレームだけであり、置き場の他のメソッド(起動時に1回だけ読むパスの引き当て)とは呼び出し頻度が違う。
//!
//! ファイルシステムと現在時刻へ触るのはこの1箇所だけである。触る場所を置き場の中へ閉じることで、呼び出し側が複写の順序や公開完了の通知を知らずに済む。
//!
//! 通常のコンパイルと同じ公開契約に合わせ、生成物を書き終えた後に生成台帳の更新日時を進める。

use std::path::Path;
use std::time::SystemTime;

use super::実行時アセットの置き場;
use crate::cli::差し替える生成物の対;
use crate::error::起動エラー;
use blitz_engine::実行時アセットの公開完了印;

impl 実行時アセットの置き場 {
    /// 対が指す複写元の生成物で複写先の生成物を上書きし、最後に生成台帳で公開完了を通知する。
    pub(crate) fn 生成物を差し替える(&self, 対: &差し替える生成物の対) -> Result<(), 起動エラー> {
        let 元 = self.生成物のパス(対.複写元());
        let 先 = self.生成物のパス(対.複写先());
        std::fs::copy(&元, &先)
            .map_err(|誤り| 起動エラー::アセット書き換え失敗(format!("{} -> {}: {誤り}", 元.display(), 先.display())))?;
        更新日時を現在時刻へ進める(&self.ディレクトリ.join(実行時アセットの公開完了印::ファイル名()))
    }
}

fn 更新日時を現在時刻へ進める(先: &Path) -> Result<(), 起動エラー> {
    let ファイル = std::fs::File::options()
        .write(true)
        .open(先)
        .map_err(|誤り| 起動エラー::アセット書き換え失敗(format!("{}: {誤り}", 先.display())))?;
    ファイル
        .set_modified(SystemTime::now())
        .map_err(|誤り| 起動エラー::アセット書き換え失敗(format!("{}: {誤り}", 先.display())))
}
