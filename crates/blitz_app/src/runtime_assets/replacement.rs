//! 置き場の中で生成物1つを別の生成物で上書きする局面。呼ばれるのはホットリロードの検収が書き換えを求めた
//! フレームだけであり、置き場の他のメソッド(起動時に1回だけ読むパスの引き当て)とは呼び出し頻度が違う。
//!
//! ファイルシステムへ触るのはこの1箇所だけである。触る場所を置き場の中へ閉じることで、呼び出し側が複写の順序や公開完了の通知を知らずに済む。
//!
//! 通常のコンパイルと同じ公開契約に合わせ、生成物を書き終えた後に生成台帳の内容を変える。

use std::path::{Path, PathBuf};

use super::実行時アセットの置き場;
use crate::cli::差し替える生成物の対;
use crate::error::起動エラー;
use blitz_engine::実行時アセットの公開完了印;

impl 実行時アセットの置き場 {
    /// 対が指す複写元の生成物で複写先の生成物を上書きし、最後に生成台帳で公開完了を通知する。
    pub(crate) fn 生成物を差し替える(&self, 対: &差し替える生成物の対) -> Result<(), 起動エラー> {
        let 元 = self.生成物のパス(対.複写元());
        let 先 = self.生成物のパス(対.複写先());
        std::fs::copy(&元, &先)
            .map_err(|誤り| 起動エラー::アセット書き換え失敗(format!("{} -> {}: {誤り}", 元.display(), 先.display())))?;
        公開完了印の内容を変える(&self.ディレクトリ.join(実行時アセットの公開完了印::ファイル名()))
    }
}

fn 公開完了印の内容を変える(先: &Path) -> Result<(), 起動エラー> {
    let mut 内容 = std::fs::read(先).map_err(|誤り| 書き換え失敗(先, 誤り))?;
    let 改行位置 = 内容
        .iter()
        .position(|値| *値 == b'\n')
        .ok_or_else(|| 起動エラー::アセット書き換え失敗(format!("{}: 生成台帳の形式宣言に改行が無い", 先.display())))?;
    // 形式宣言の末尾の空白は解析結果を変えず、内容比較だけを確実に変える。
    内容.insert(改行位置, b' ');
    let 一時 = 一時ファイルのパス(先);
    std::fs::write(&一時, 内容).map_err(|誤り| 書き換え失敗(&一時, 誤り))?;
    std::fs::rename(&一時, 先).map_err(|誤り| 書き換え失敗(先, 誤り))
}

fn 一時ファイルのパス(先: &Path) -> PathBuf {
    let mut 綴り = 先.as_os_str().to_os_string();
    綴り.push(実行時アセットの公開完了印::公開前の一時ファイル接尾辞());
    PathBuf::from(綴り)
}

fn 書き換え失敗(先: &Path, 誤り: std::io::Error) -> 起動エラー {
    起動エラー::アセット書き換え失敗(format!("{}: {誤り}", 先.display()))
}
