//! 開発用UIに重ねる、操作の一覧とカメラの系統と移動とカメラの計器の面。担当するのは値を並べることだけであり、
//! 値の出どころはゲーム配線の計器である(判断13)。開発パネルと同じくF3で表示を切り替える。

use blitz_game::遮蔽の判定;

use crate::game::{カメラの計器, 直前の描画のカメラ, 移動とカメラの計器};

const 操作の一覧: [&str; 8] = [
    "矢印キー: 歩く",
    "Enter: 決定",
    "Escape: 取り消し(終了確認を開く・閉じる)",
    "W/S: カメラを上下に回す",
    "A/D: カメラを左右に回す",
    "Q/E・ホイール: カメラを近づける・遠ざける",
    "マウス左ドラッグ: カメラを回す",
    "F3: 開発用UI / F4: カメラの系統を切り替える",
];

pub(super) fn 内容を描く(ctx: &egui::Context, 計器: &移動とカメラの計器) {
    egui::Window::new("移動とカメラ").resizable(false).show(ctx, |ui| 計器を並べる(ui, 計器));
}

fn 計器を並べる(ui: &mut egui::Ui, 計器: &移動とカメラの計器) {
    ui.label("操作の一覧");
    for 行 in 操作の一覧 {
        ui.label(format!("  {行}"));
    }
    ui.separator();
    カメラの計器を並べる(ui, &計器.カメラ);
}

fn カメラの計器を並べる(ui: &mut egui::Ui, カメラ: &カメラの計器) {
    ui.label(format!("カメラの系統: {}", カメラ.系統.表示名()));
    match カメラ.直前の描画 {
        直前の描画のカメラ::まだ描いていない => {
            ui.label("カメラの計器: まだ1度も決めていない");
        }
        直前の描画のカメラ::描いた {
            理想距離, 表示距離, 判定
        } => {
            ui.label(format!("理想距離: {:.2} m", 理想距離.値()));
            ui.label(format!("表示距離: {:.2} m", 表示距離.値()));
            ui.label(format!("遮蔽: {}", 判定の呼び名(判定)));
        }
    }
    ui.label(format!("完全性で保った描画の数: {}", カメラ.完全性で保った描画の数));
}

fn 判定の呼び名(判定: 遮蔽の判定) -> &'static str {
    match 判定 {
        遮蔽の判定::遮られていない => "遮られていない",
        遮蔽の判定::遮られている => "遮られている(表示距離を縮めた)",
        遮蔽の判定::評価できず前の表示距離を保った => "評価できず前の表示距離を保った",
    }
}
