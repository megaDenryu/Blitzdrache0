//! そのフレームに画面へ重ねるものの一式と、それを描く順。担当するのは、開発パネルが要る値とゲームの画面が要る値を
//! 1つに束ねて運ぶことと、重ねる順を決めることである。eguiとwinitの統合そのものは親モジュールが持つ。
//!
//! 2つを別々の引数で受け取らないのは、重ねるものが増えるたびに描画データの組み立ての引数が伸びるためである。

use super::game_screen::ゲーム画面の表示内容;
use super::stats::開発UI統計;
use super::{game_screen, panel};

pub(crate) struct 画面へ重ねる内容 {
    pub(crate) 開発パネルの統計: 開発UI統計, // パネルを表示しないフレームでも作るのは、計器の取り出しがフレームの決まった位置にあり、表示の有無で読む時点を変えないため
    pub(crate) ゲーム画面: Option<ゲーム画面の表示内容>, // ゲームを遊ばない起動ではNoneであり、eguiはゲームの画面を1つも描かない
}

impl 画面へ重ねる内容 {
    /// 重ねるものが1つも無ければ真。この場合はeguiを1度も実行しない。
    pub(super) fn 重ねるものが無いか(&self, 開発パネルを表示するか: bool) -> bool {
        !開発パネルを表示するか && self.ゲーム画面.is_none()
    }

    /// そのフレームに重ねるものを順に描く。開発パネルを後に描くのは、ゲームの画面と重なる位置でも計器が読めるようにするためである。
    pub(super) fn 順に描く(
        &self,
        ctx: &egui::Context,
        開発パネルを表示するか: bool,
        露出: &mut crate::cli::露出倍率,
        ブレンド: &mut crate::cli::アニメーションのブレンド係数,
    ) {
        if let Some(表示内容) = self.ゲーム画面 {
            game_screen::内容を描く(ctx, 表示内容);
        }
        if 開発パネルを表示するか {
            panel::内容を描く(ctx, &self.開発パネルの統計, 露出, ブレンド);
        }
    }
}
