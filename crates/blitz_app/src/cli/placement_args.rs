//! 世界とカメラの配置をずらす起動引数の解析と、その設定一式。
//! CLI層でこのファイルだけが数学DDDの位置の語彙(大域ワールド位置・メートル)を扱い、他の値引数は経路・件数・モードを扱う。
//! 触れる引数は`--global-offset`と`--camera-nudge`と`--camera-pitch`と`--camera-yaw`の4つに限る。

use std::slice::Iter;

use blitz_math::{メートル, ラジアン, 大域メートル, 大域ワールド位置};

use super::value_args::次の値を読む;
use super::起動引数エラー;

/// 世界全体とカメラへ加える平行移動。原点移動不変性の検査は、km級の大域ずらし量で描画が一致することと、
/// 微小なカメラずれで描画が実際に変わることの両方を測るため、この2つを組にして扱う。
pub(crate) struct 平行移動起動設定 {
    /// `--global-offset <x> <y> <z>`で世界全体へ加える平行移動。既定は原点。
    pub(crate) 大域ずらし量: 大域ワールド位置,
    /// `--camera-nudge <メートル>`でカメラの注視点と視点をX方向へずらす量。既定は0。
    pub(crate) カメラずれ: メートル,
    /// `--camera-pitch <度>`でシーン既定の姿勢へさらに加える俯角。負で視線が上を向く。既定は0。
    /// 空の検収は地平線より上の空を画面へ入れる必要があり、見下ろす既定の構図では上向きの成分が1つも入らない。
    pub(crate) カメラ俯角差分: ラジアン,
    /// `--camera-yaw <度>`でシーン既定の姿勢へさらに加える方位角。既定は0。
    /// 太陽円盤の画素検収は低い太陽を画面へ入れる必要があり、俯角だけでは東西の向きを選べない。
    pub(crate) カメラ方位差分: ラジアン,
}

impl 平行移動起動設定 {
    pub(super) fn 既定値() -> Self {
        Self {
            大域ずらし量: 大域ワールド位置::原点(),
            カメラずれ: メートル::生成する(0.0),
            カメラ俯角差分: ラジアン::生成する(0.0),
            カメラ方位差分: ラジアン::生成する(0.0),
        }
    }
}

/// `--global-offset <x> <y> <z>`の3成分を読む。軸ごとに違う値を与えられるため、軸の取り違えが同値の置換に化けない。
pub(super) fn global_offset引数を処理する(引数: &mut Iter<String>) -> Result<大域ワールド位置, 起動引数エラー> {
    let mut 成分 = [0.0_f64; 3];
    for 保存先 in &mut 成分 {
        let 値 = 次の値を読む(引数, "--global-offset", 起動引数エラー::大域ずらし量不正)?;
        let 数 = 値.parse::<f64>().map_err(|_| 起動引数エラー::大域ずらし量不正(値.clone()))?;
        if !数.is_finite() {
            return Err(起動引数エラー::大域ずらし量不正(format!("有限値でない: {値}")));
        }
        *保存先 = 数;
    }
    let [x, y, z] = 成分.map(大域メートル::生成する);
    Ok(大域ワールド位置::生成する(x, y, z))
}

/// `--camera-pitch <度>`の値を読む。シーンごとの初期姿勢へ加える俯角であり、空を画面へ入れるために使う。
pub(super) fn camera_pitch引数を処理する(引数: &mut Iter<String>) -> Result<ラジアン, 起動引数エラー> {
    let 値 = 次の値を読む(引数, "--camera-pitch", 起動引数エラー::カメラ俯角不正)?;
    let 度 = 値.parse::<f32>().map_err(|_| 起動引数エラー::カメラ俯角不正(値.clone()))?;
    if !度.is_finite() || 度.abs() > 90.0 {
        return Err(起動引数エラー::カメラ俯角不正(
            format!("有限かつ絶対値90度以下でない: {値}"),
        ));
    }
    Ok(ラジアン::度から(度))
}

/// `--camera-yaw <度>`の値を読む。シーンごとの初期姿勢へ加える方位角であり、太陽を画面へ入れるために使う。
pub(super) fn camera_yaw引数を処理する(引数: &mut Iter<String>) -> Result<ラジアン, 起動引数エラー> {
    let 値 = 次の値を読む(引数, "--camera-yaw", 起動引数エラー::カメラ方位不正)?;
    let 度 = 値.parse::<f32>().map_err(|_| 起動引数エラー::カメラ方位不正(値.clone()))?;
    if !度.is_finite() || 度.abs() > 360.0 {
        return Err(起動引数エラー::カメラ方位不正(
            format!("有限かつ絶対値360度以下でない: {値}"),
        ));
    }
    Ok(ラジアン::度から(度))
}

/// `--camera-nudge <メートル>`の値を読む。カメラだけを既知量ずらし、描画が実際に変わることを測るための平行移動である。
pub(super) fn camera_nudge引数を処理する(引数: &mut Iter<String>) -> Result<メートル, 起動引数エラー> {
    let 値 = 次の値を読む(引数, "--camera-nudge", 起動引数エラー::カメラずれ不正)?;
    let ずれ = 値.parse::<f32>().map_err(|_| 起動引数エラー::カメラずれ不正(値.clone()))?;
    if !ずれ.is_finite() {
        return Err(起動引数エラー::カメラずれ不正(format!("有限値でない: {値}")));
    }
    Ok(メートル::生成する(ずれ))
}
