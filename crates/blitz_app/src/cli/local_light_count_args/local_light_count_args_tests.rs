//! 局所光の件数の起動指定の解析の検査。確かめるのは、上限までの件数を受けること、上限を超えた件数と
//! 数として読めない語と値の欠落を型付きの失敗にすることである。
//!
//! 上限の拒否をここで検査するのは、越えた件数をレンダラーの奥の失敗として受け取ると、直すべき場所が
//! 起動引数であることが読み取れないためである。

#![allow(clippy::unwrap_used)]

use super::super::局所光の件数の起動指定;
use super::引数を処理する;

fn 解析する(語一覧: &[&str]) -> Result<局所光の件数の起動指定, String> {
    let 引数一覧: Vec<String> = 語一覧.iter().map(|語| (*語).to_string()).collect();
    引数を処理する(&mut 引数一覧.iter()).map_err(|誤り| 誤り.to_string())
}

#[test]
fn 上限までの件数を受ける() {
    for 件数 in [0_usize, 1, 8, 63, 64] {
        assert_eq!(
            解析する(&[&件数.to_string()]),
            Ok(局所光の件数の起動指定::件数を上書きする(件数)),
            "{件数}件を受けなかった"
        );
    }
}

#[test]
fn 上限を超えた件数を型付きの失敗にする() {
    assert!(解析する(&["65"]).is_err());
    assert!(解析する(&["1000"]).is_err());
}

#[test]
fn 数として読めない語を型付きの失敗にする() {
    assert!(解析する(&["八"]).is_err());
    assert!(解析する(&["-1"]).is_err());
}

#[test]
fn 値の欠落を型付きの失敗にする() {
    assert!(解析する(&[]).is_err());
}
