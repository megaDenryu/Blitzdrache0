//! CLI引数から得る型: 起動モード・起動設定一式。

use super::{ストリーミング起動設定, 布モード, 平行移動起動設定, 描画対象数, 粒子表示モード};
use std::path::PathBuf;

const 既定シェーダー監視パス: &str = "shaders/scene.slang";
const 既定シーン名: &str = "quad";
const 既定アセットルート: &str = "target/runtime_assets";

/// 起動時に指定できる実行モード。
#[derive(Debug, Clone, Copy)]
pub(crate) enum 起動モード {
    /// ユーザーが閉じるまで無期限に実行する。
    無期限実行,
    /// 指定フレーム数を描画したら自動終了する(DoDのスモーク検証用)。
    スモーク実行 { フレーム数: u32 },
    /// 自己操作やピクセル判定を行わず、指定フレーム数を描画して計測する。
    ベンチ実行 { フレーム数: u32 },
}

/// CLI引数から得た起動設定一式。
pub(crate) struct 起動設定 {
    pub(crate) モード: 起動モード,
    /// ホットリロードの監視対象となるエントリファイル。既定は`shaders/scene.slang`(存在しなければ監視無効)。
    /// `import`で参照される他の.slangファイル(`pbr.slang`等)はこのエントリファイルと同じディレクトリから解決されるため、個別指定はしない。ディレクトリ全体をmtime走査で監視する。
    pub(crate) シェーダー監視パス: PathBuf,
    /// 表示するシーンのアセットID。既定は`quad`(常に存在し決定的)。
    pub(crate) シーン名: String,
    /// カタログの実行時アセットパスの基準ディレクトリ。既定は`target/runtime_assets`。
    pub(crate) アセットルート: PathBuf,
    pub(crate) 描画対象数: Option<描画対象数>,
    /// `--unlit`指定でfalse。既定はtrue(PBRライティング有効、判断26)。
    pub(crate) ライティング有効: bool,
    /// 粒子系GPUパスで表示する検証対象。既定はなし。
    pub(crate) 粒子表示: 粒子表示モード,
    /// `--report-gpu-times`指定でtrue。既定はfalse(パス別GPU時間の終了時コンソール出力、判断30)。
    pub(crate) gpu時間報告: bool,
    /// `--report-frame-times`指定でtrue。最初の120フレームを除いたCPU側フレーム間隔分布を終了時に出力する。
    pub(crate) フレーム時間報告: bool,
    /// `--report-memory`指定でtrue。Vulkan専用メモリ確保の現在数・上限・用途別量を終了時に出力する。
    pub(crate) gpuメモリ報告: bool,
    /// `--dev-ui`指定でtrue。既定はfalse(開発用UIの起動時有効化、判断34。実行中はF3でも切替可能)。
    pub(crate) 開発ui初期有効: bool,
    /// `--dump-frame <ベース名>`指定で、最終フレーム(--frames必須)の読み戻し画像を`<ベース名>.raw`(RGBA8連結)と`<ベース名>.size`(幅 高さ)へ書き出す。既定はNone。
    pub(crate) フレームダンプ先: Option<PathBuf>,
    /// `--no-post`指定でfalse。既定はtrue(HDR中間バッファ+トーンマップパス、判断38・39)。falseならシーンが直接スワップチェーンへ描く構成に戻る(DoD「チェーンの追加・削除可能」の機械実証)。
    pub(crate) ポスト処理有効: bool,
    /// `--exposure <倍率>`指定で変更。既定は1.0(トーンマップ前にHDR輝度へ掛ける露出倍率、判断39)。
    pub(crate) 露出: f32,
    /// `--blend <0..1>`指定で変更。既定は0.0(アニメーションクリップ2本のブレンド係数、判断45)。
    pub(crate) ブレンド: f32,
    /// 布シミュレーションの方式(判断52・56)。`--cloth`=吊るし布(全シーン可)、`--cloth-cape`=マント(fox限定、キャラ追従)。既定はなし。
    pub(crate) 布モード: 布モード,
    /// `--report-display-timing`指定でtrue。提示IDと提示待機で実表示間隔を測る。
    ///
    /// 注意: この計測は`vkWaitForPresentKHR`で表示まで描画ループを止める(2026-07-25の実測で毎フレーム
    /// 約16ms)。フレームペーシングを変えうるため、既存の性能時系列と比較する値を採るときは指定しない。
    /// この指定の有無で条件が変わるので、両条件を比べるときは交互に実行して機材側の時間変動を打ち消すこと。
    pub(crate) 実表示時間報告: bool,
    /// `--window-rebuild`指定でtrue。既定はfalse。ポスト処理を有効に保ったままリサイズ・最小化・復帰を踏み、ピクセル判定を持たない検証計画を選ぶ(合否はvalidation件数とGPUメモリ残数で決まる)。
    pub(crate) ウィンドウ再構築検証有効: bool,
    /// チャンクストリーミングの有効化と容量上限。既定は無効(既存のスモークとベンチの挙動を変えない)。
    pub(crate) ストリーミング: ストリーミング起動設定,
    /// 世界全体とカメラへ加える平行移動。大域オフセットはカメラ大域原点・照明の大域位置と、起動時シーンとチャンク束の描画アンカーへ効く。
    /// アンカーは所有チャンクから導出した後にこの平行移動を合成する。チャンク格子と必要集合の判定は平行移動を含まない世界座標で行うため、位置源には加えない。
    pub(crate) 平行移動: 平行移動起動設定,
}

impl 起動設定 {
    pub(super) fn 既定値() -> Self {
        Self {
            モード: 起動モード::無期限実行,
            シェーダー監視パス: PathBuf::from(既定シェーダー監視パス),
            シーン名: 既定シーン名.to_string(),
            アセットルート: PathBuf::from(既定アセットルート),
            描画対象数: None,
            ライティング有効: true,
            粒子表示: 粒子表示モード::なし,
            gpu時間報告: false,
            フレーム時間報告: false,
            gpuメモリ報告: false,
            開発ui初期有効: false,
            フレームダンプ先: None,
            ポスト処理有効: true,
            露出: 1.0,
            ブレンド: 0.0,
            布モード: 布モード::なし,
            実表示時間報告: false,
            ウィンドウ再構築検証有効: false,
            ストリーミング: ストリーミング起動設定::既定値(),
            平行移動: 平行移動起動設定::既定値(),
        }
    }
}
