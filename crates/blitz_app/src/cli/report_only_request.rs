//! 描画の設定を1つも読まずに答えられる起動要求を見分ける工程。受け取るのは引数の並び、返すのは
//! 該当する起動要求である。該当しなければ`None`を返し、呼び出し元が描画実行の解析へ進む。
//!
//! 描画実行の解析と分けるのは、ここに挙げる要求がウィンドウもシーンも露出も1つも読まないためである。
//! 同じ関数で扱うと、描画の設定を組み立ててから捨てる経路が生まれ、描画の引数の誤りがこれらの要求でも
//! 失敗として現れる。値を伴う引数を1つも取らないため、走査は語の一致だけで済む。
//!
//! 注意: 選ぶ順はこの一覧の並びであって、CLIに書いた並びではない。2つ以上を同時に指定した起動が、
//! 書く順によって別の報告を出すことを避けるためである。この順序は`report_only_request_tests`が固定する。

use super::launch_request::起動要求;

/// 報告だけを求める引数を、選ぶ順に並べた一覧。天空状態と太陽天頂区間の跨ぎはGPUを1度も使わず、
/// 残りはウィンドウを作らずにウィンドウなし実行のGPUだけを使う。
const 選ぶ順の引数一覧: [&str; 5] = [
    "--report-sky-state",
    "--report-atmosphere-lut",
    "--report-distant-environment",
    "--report-derived-environment",
    "--report-sun-zenith-crossings",
];

/// 一覧の先頭から順に、その引数が並びのどこかに在るかを見る。最初に見つかった引数の要求を返す。
pub(super) fn 報告だけの要求を見分ける(引数一覧: &[String]) -> Option<起動要求> {
    選ぶ順の引数一覧
        .iter()
        .find(|引数名| 引数一覧.iter().any(|引数値| 引数値 == *引数名))
        .and_then(|引数名| 引数から要求を作る(引数名))
}

/// 引数1つが表す報告だけの要求。
///
/// ワイルドカードの枝を持つのは、引数の語がプロセス境界の外から来る値であり、網羅を型で保証できないためである。
fn 引数から要求を作る(引数値: &str) -> Option<起動要求> {
    match 引数値 {
        "--report-sky-state" => Some(起動要求::天空状態報告),
        "--report-atmosphere-lut" => Some(起動要求::大気のベイク済み画像報告),
        "--report-distant-environment" => Some(起動要求::遠方環境報告),
        "--report-derived-environment" => Some(起動要求::派生表現報告),
        "--report-sun-zenith-crossings" => Some(起動要求::太陽天頂区間の跨ぎ報告),
        _ => None,
    }
}
