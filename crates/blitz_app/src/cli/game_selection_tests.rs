//! `--game`の解析の検証。指定が無い起動が「ゲームを遊ばない」のままであることと、知らない名前を黙って無視しないことを見る。

use super::game_operation_source::ゲーム操作の出どころ;
use super::{引数を解析する, 起動要求, 遊ぶゲームの指定};

fn 遊ぶゲームを解析する(引数一覧: &[String]) -> 遊ぶゲームの指定 {
    match 引数を解析する(引数一覧) {
        Ok(起動要求::描画実行(設定)) => 設定.遊ぶゲーム,
        Ok(報告) => panic!("描画実行の要求になるはず(報告の種別{})", 報告.呼び名()),
        Err(誤り) => panic!("有効な引数は解析できるはず: {誤り}"),
    }
}

/// 反証: 既定がゲームを遊ぶ側に倒れていると、既存の全ての入口がゲーム更新を回してしまう。
#[test]
fn 指定が無ければゲームを遊ばない() {
    assert_eq!(遊ぶゲームを解析する(&[]), 遊ぶゲームの指定::ゲームを遊ばない);
    let 既存の入口 = ["--frames".to_string(), "3".to_string(), "--scene".to_string(), "quad".to_string()];
    assert_eq!(遊ぶゲームを解析する(&既存の入口), 遊ぶゲームの指定::ゲームを遊ばない);
}

#[test]
fn fox_tourはキツネの場所巡りを選ぶ() {
    let 引数 = ["--game".to_string(), "fox_tour".to_string()];
    let 期待 = 遊ぶゲームの指定::キツネの場所巡り(ゲーム操作の出どころ::実行時の入力);
    assert_eq!(遊ぶゲームを解析する(&引数), 期待);
}

/// 反証: 台本の入口が実行時の入力と同じ指定になると、検収の実行が実ウィンドウの操作で揺れる。
#[test]
fn fox_tour_scriptedは決定的な台本の操作を選ぶ() {
    let 引数 = ["--game".to_string(), "fox_tour_scripted".to_string()];
    let 期待 = 遊ぶゲームの指定::キツネの場所巡り(ゲーム操作の出どころ::決定的な台本);
    assert_eq!(遊ぶゲームを解析する(&引数), 期待);
}

/// 反証: 知らない名前を読み飛ばすと、綴りを誤った起動が黙ってゲーム無しで走る。
#[test]
fn 知らないゲーム名は誤りになる() {
    let 引数 = ["--game".to_string(), "fox-tour".to_string()];
    assert!(引数を解析する(&引数).is_err());
}

#[test]
fn 値の無いgame引数は誤りになる() {
    assert!(引数を解析する(&["--game".to_string()]).is_err());
}

#[test]
fn 表示名は日本語で答える() {
    let 指定 = 遊ぶゲームの指定::キツネの場所巡り(ゲーム操作の出どころ::実行時の入力);
    assert_eq!(指定.表示名(), "キツネの場所巡り");
}
