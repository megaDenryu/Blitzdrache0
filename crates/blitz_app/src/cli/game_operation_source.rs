//! ゲームの操作がどこから来るかの指定。担うのは出どころの別だけであり、その出どころが何を押すかも、押した入力を
//! そのフレームへ適用するかも持たない(適用の可否は`input/game_intent_policy.rs`が持つ)。
//!
//! 台本の枝を置くのは、フレーム数の決まった実行が実ウィンドウの入力を1つも通さないためである。通さない実行で
//! キツネを歩かせられないと、動く個体の変換がGPUへ届いていることを絵で見る入口が作れない。
//! 台本は実時間もウィンドウも読まずゲーム更新の回数だけで決まるため、同じ引数の実行は必ず同じ進行になる。

/// ゲームの操作の出どころ。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum ゲーム操作の出どころ {
    実行時の入力, // 実ウィンドウへ届く操作。フレーム数の決まった実行では適用方針がこの操作を1つも通さない
    決定的な台本, // 検収が与える決定的な台本。適用方針を通らず、ゲーム更新の回数だけからそのフレームの操作が決まる
}
