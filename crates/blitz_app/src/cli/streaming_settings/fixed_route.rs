//! km級の固定経路を表す起動設定。水平面の始点と終点、および1フレームの移動量を持つ。

use blitz_engine::固定経路;
use blitz_math::{大域メートル, 大域ワールド位置};

#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 固定経路起動設定 {
    pub(crate) 始点東メートル: f64,
    pub(crate) 始点南メートル: f64,
    pub(crate) 終点東メートル: f64,
    pub(crate) 終点南メートル: f64,
    pub(crate) 一フレーム移動量メートル: f64,
}

impl 固定経路起動設定 {
    pub(crate) const fn 既定値() -> Self {
        Self {
            始点東メートル: -150.0,
            始点南メートル: 0.0,
            終点東メートル: 250.0,
            終点南メートル: 0.0,
            一フレーム移動量メートル: 5.0,
        }
    }

    pub(crate) fn 経路を作る(self) -> Result<固定経路, blitz_engine::固定経路エラー> {
        固定経路::生成する(
            経路端点(self.始点東メートル, self.始点南メートル),
            経路端点(self.終点東メートル, self.終点南メートル),
            大域メートル::生成する(self.一フレーム移動量メートル),
        )
    }
}

fn 経路端点(東メートル: f64, 南メートル: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(東メートル),
        大域メートル::生成する(0.0),
        大域メートル::生成する(南メートル),
    )
}
