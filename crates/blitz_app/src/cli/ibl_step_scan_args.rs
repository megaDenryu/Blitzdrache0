//! `--ibl-step-scan <最初の境界番号>,<境界の本数>`の解析。担当する工程は「1つの語を段差走査範囲へ直す」ことである。
//!
//! 境界そのものでなく一覧の中の番号で受け取るのは、どの区間識別が一日で跨がれるかを起動側が決めないためである。
//! 番号の並びは`--report-sun-zenith-boundaries`が出す一覧と同じであり、範囲が一覧の外へ出たときは
//! 走査の組み立てが名指しして落とす。

use std::slice::Iter;

use super::value_args::次の値を読む;
use super::起動モード;
use super::起動引数エラー;
use crate::app::time_of_day::段差走査範囲;

pub(super) fn 引数を処理する(引数: &mut Iter<String>) -> Result<起動モード, 起動引数エラー> {
    let 値 = &次の値を読む(引数, "--ibl-step-scan", 起動引数エラー::段差走査範囲不正)?;
    let 成分一覧: Vec<&str> = 値.split(',').collect();
    let [最初の境界番号, 境界の本数] = 成分一覧.as_slice() else {
        return Err(起動引数エラー::段差走査範囲不正(
            format!("最初の境界番号,境界の本数の2つでない: {値}"),
        ));
    };
    Ok(起動モード::段差走査実行 {
        走査範囲: 段差走査範囲::生成する(数を読む(最初の境界番号, 値)?, 数を読む(境界の本数, 値)?)?,
    })
}

fn 数を読む(語: &str, 全体: &str) -> Result<u16, 起動引数エラー> {
    語.trim()
        .parse()
        .map_err(|誤り| 起動引数エラー::段差走査範囲不正(format!("{全体}の成分を数として読めない: {誤り}")))
}
