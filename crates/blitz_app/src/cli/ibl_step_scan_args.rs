//! `--ibl-step-scan <最初の跨ぎ番号>,<跨ぎの件数>`と`--ibl-step-control <跨ぎ番号>`の解析。
//! 担当する工程は「1つの語を段差走査の指定へ直す」ことである。
//!
//! 跨ぎそのものでなく一覧の中の番号で受け取るのは、どの区間識別をどの向きで跨ぐかを起動側が決めないためである。
//! 番号の並びは`--report-sun-zenith-crossings`が出す一覧と同じであり、指定が一覧の外へ出たときは
//! 走査の組み立てが名指しして落とす。

use std::slice::Iter;

use super::value_args::次の値を読む;
use super::{起動モード, 起動引数エラー};
use crate::app::time_of_day::段差走査の指定;

/// 引数名で範囲と対照を分ける。どちらも起動モードを返すため、値の読み方だけが違う。
pub(super) fn 引数を処理する(引数: &mut Iter<String>, 引数名: &str) -> Result<起動モード, 起動引数エラー> {
    let 値 = &次の値を読む(引数, 引数名, 起動引数エラー::段差走査範囲不正)?;
    if 引数名 == "--ibl-step-control" {
        return Ok(起動モード::段差走査実行 {
            走査指定: 段差走査の指定::対照 {
                跨ぎ番号: 数を読む(値, 値)?
            },
        });
    }
    let 成分一覧: Vec<&str> = 値.split(',').collect();
    let [最初の跨ぎ番号, 跨ぎの件数] = 成分一覧.as_slice() else {
        return Err(起動引数エラー::段差走査範囲不正(
            format!("最初の跨ぎ番号,跨ぎの件数の2つでない: {値}"),
        ));
    };
    Ok(起動モード::段差走査実行 {
        走査指定: 段差走査の指定::範囲を作る(数を読む(最初の跨ぎ番号, 値)?, 数を読む(跨ぎの件数, 値)?)?,
    })
}

fn 数を読む(語: &str, 全体: &str) -> Result<u16, 起動引数エラー> {
    語.trim()
        .parse()
        .map_err(|誤り| 起動引数エラー::段差走査範囲不正(format!("{全体}の成分を数として読めない: {誤り}")))
}
