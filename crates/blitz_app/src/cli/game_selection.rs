//! 起動時に「どのゲームを遊ぶか」を選ぶ指定と、その引数の読み取りを所有する。
//!
//! 指定が無い状態を`Option`でなく枝で持つのは、ゲーム更新が1つも走らないことを型で保つためである。
//! 既存の入口(スモーク・ベンチ・段差走査・報告)はどれもこの指定を持たず、判定値が1つも変わらない。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「第1段階の定義」。

use std::slice::Iter;

use super::{value_args, 起動引数エラー};

/// `--game`に渡すクソゲー1本目の名前。CLIはプロセス境界のためASCIIで書く。
const キツネの場所巡りの引数値: &str = "fox_tour";

/// 起動時に選んだ、遊ぶゲーム。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 遊ぶゲームの指定 {
    /// `--game`の指定が無い起動。ゲーム更新を1つも行わない。
    ゲームを遊ばない,
    /// クソゲー1本目。
    キツネの場所巡り,
}

impl 遊ぶゲームの指定 {
    /// 報告へ出す日本語の表示名。
    pub(crate) fn 表示名(self) -> &'static str {
        match self {
            Self::ゲームを遊ばない => "ゲームを遊ばない",
            Self::キツネの場所巡り => "キツネの場所巡り",
        }
    }
}

/// `--game`の値から遊ぶゲームを選ぶ。知らない名前は黙って無視せず型付きエラーにする。
pub(in crate::cli) fn game引数を処理する(引数: &mut Iter<String>) -> Result<遊ぶゲームの指定, 起動引数エラー> {
    let 値 = value_args::次の値を読む(引数, "--game", 起動引数エラー::遊ぶゲーム不正)?;
    match 値.as_str() {
        キツネの場所巡りの引数値 => Ok(遊ぶゲームの指定::キツネの場所巡り),
        知らない名前 => Err(起動引数エラー::遊ぶゲーム不正(format!(
            "知らないゲーム名({知らない名前})。選べるのは{キツネの場所巡りの引数値}だけである"
        ))),
    }
}
