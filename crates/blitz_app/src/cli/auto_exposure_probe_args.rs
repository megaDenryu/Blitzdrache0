//! `--auto-exposure-probe <赤,緑,青>`の解析。担当する工程は「1つの語を線形RGBの探り色へ直す」ことである。
//!
//! 探り色はシーンパスのクリア色を置き換え、背景の画素をその色で埋める。自動露出の集計はその画素を数えるため、
//! CPU正本とGPUの写しがその色をどのビンへ入れたかを検収が突き合わせられる。
//! 値の選び方(積和融合の有無でビンが変わり、かつ半精度で正確に表せる組)は`xtask/src/auto_exposure/run.rs`が持つ。
//! ここは範囲(クリア色の0.0から1.0)の検査だけを行い、どの色が意味を持つかを1つも知らない。

use std::slice::Iter;

use super::value_args::次の値を読む;
use super::起動引数エラー;

pub(super) fn 引数を処理する(引数: &mut Iter<String>) -> Result<[f32; 3], 起動引数エラー> {
    let 値 = &次の値を読む(引数, "--auto-exposure-probe", 起動引数エラー::自動露出の探り色不正)?;
    let 成分一覧: Vec<&str> = 値.split(',').collect();
    let [赤, 緑, 青] = 成分一覧.as_slice() else {
        return Err(起動引数エラー::自動露出の探り色不正(
            format!("赤,緑,青の3つでない: {値}"),
        ));
    };
    Ok([成分を読む(赤, 値)?, 成分を読む(緑, 値)?, 成分を読む(青, 値)?])
}

/// クリア色の成分は0.0から1.0であり、範囲を外れた値はクリアカラーの生成が拒む。ここで名指しして落とす。
fn 成分を読む(語: &str, 全体: &str) -> Result<f32, 起動引数エラー> {
    let 値: f32 = 語
        .trim()
        .parse()
        .map_err(|誤り| 起動引数エラー::自動露出の探り色不正(format!("{全体}の成分を数として読めない: {誤り}")))?;
    if !(0.0..=1.0).contains(&値) {
        return Err(起動引数エラー::自動露出の探り色不正(
            format!("成分が0.0から1.0の外にある: {値}"),
        ));
    }
    Ok(値)
}
