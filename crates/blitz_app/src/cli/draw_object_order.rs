//! 束へ載せる描画対象の走査順。同じ描画対象の集合を、束の中でどちらの向きに並べるかを表す。
//!
//! 逆順は検収のための指定である。布の影のように「束の走査順で最初の描画対象」から資源を借りていた経路が残っていると、
//! 描画対象を並べ替えただけで絵が変わる。並べても絵が変わらないことを画素で確かめる入口が`cargo xtask cloth-shadow-order`であり、
//! この指定がその2回の実行の唯一の違いになる
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「描画段階資源の器と布専用シャドウ経路」)。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 描画対象の走査順 {
    読込順, // シーンデータに並んでいる順。既定である
    逆順,   // シーンデータの並びを逆にした順
}

impl 描画対象の走査順 {
    /// 束の中の位置から、そこへ載せる描画対象がシーンデータの何番目かを決める。
    /// 逆順は集合を逆に並べるだけであり、描画対象とその配置変換の対応は変えない。
    /// 前提: `位置`は`件数`未満である(呼び出し元が`0..件数`の走査で渡す)。
    pub(crate) fn シーン内の添字へ写す(self, 位置: usize, 件数: usize) -> usize {
        match self {
            Self::読込順 => 位置,
            Self::逆順 => 件数 - 1 - 位置,
        }
    }
}
