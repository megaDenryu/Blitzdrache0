//! 局所可視性補正まわりの起動指定。触れる状態を持たず、担うのは世界の宣言を上書きする1つの軸の語彙だけである。
/// 局所可視性補正を効かせるかどうか。既定は世界の宣言に従う。
///
/// 切れる形を残すのは、局所可視性補正を入れる前の絵と後の絵を同じ実行条件で比べるためである。
/// 世界の宣言を書き換えずに外せると、判定値を持つ検収がどちらの条件でも同じ入口から走る。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 局所可視性の起動指定 {
    /// 既定。世界が宣言した拡散間接方式をそのまま使う。
    宣言に従う,
    /// `--no-ssao`。世界が局所可視性補正を宣言していても環境のみで描く。
    環境のみで描く,
}
