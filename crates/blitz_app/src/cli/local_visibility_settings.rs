//! 局所可視性補正まわりの起動指定。触れる状態を持たず、担うのは世界の宣言を上書きする軸と、検収が可視度を
//! 一定値へ固定する軸の2つを1組で運ぶことだけである。
//!
//! 2つを1つに束ねるのは、どちらも「世界が宣言した局所可視性補正をそのまま効かせるか」を動かす指定であり、
//! 起動設定の平らな並びへ別々に置くと2つの関係が読めなくなるためである。CLIの語からこの2つを作る工程も
//! 同じファイルに置く(`shadow_args`・`streaming_settings`と同じ様式)。形は合成深度の注入と突き合わせを、
//! 符号値は拡散間接だけへ掛かることの反証を担う。

use std::slice::Iter;

use blitz_render::local_visibility::{局所可視度の上書き, 局所可視度の符号値};

use super::value_args::次の値を読む;
use super::起動引数エラー;
use crate::reports::local_visibility::合成深度の形;

/// 局所可視性補正を効かせるかどうか。既定は世界の宣言に従う。
///
/// 切れる形を残すのは、局所可視性補正を入れる前の絵と後の絵を同じ実行条件で比べるためである。
/// 世界の宣言を書き換えずに外せると、判定値を持つ検収がどちらの条件でも同じ入口から走る。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 拡散間接方式の起動上書き {
    宣言に従う,     // 既定。世界が宣言した拡散間接方式をそのまま使う
    環境のみで描く, // --no-ssao。世界が局所可視性補正を宣言していても環境のみで描く
}

/// 局所可視性補正の起動指定一式。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 局所可視性の起動指定 {
    pub(crate) 方式の上書き: 拡散間接方式の起動上書き,
    pub(crate) 可視度の固定: 局所可視度の上書き, // --local-visibility-fixed <符号値>で全画素の局所可視度をその値へ固定する。既定は上書きしない
}

impl 局所可視性の起動指定 {
    pub(crate) fn 既定値() -> Self {
        Self {
            方式の上書き: 拡散間接方式の起動上書き::宣言に従う,
            可視度の固定: 局所可視度の上書き::上書きしない,
        }
    }
}

pub(in crate::cli) fn 形の引数を処理する(引数: &mut Iter<String>) -> Result<合成深度の形, 起動引数エラー> {
    let 値 = 次の値を読む(引数, "--local-visibility-shape", 起動引数エラー::局所可視性の検収指定不正)?;
    match 値.as_str() {
        "plane" => Ok(合成深度の形::平面),
        "step" => Ok(合成深度の形::段差),
        "sphere" => Ok(合成深度の形::球),
        "concave" => Ok(合成深度の形::凹面),
        その他 => Err(起動引数エラー::局所可視性の検収指定不正(format!(
            "形は plane|step|sphere|concave のいずれかである: {その他}"
        ))),
    }
}

pub(in crate::cli) fn 固定の引数を処理する(引数: &mut Iter<String>) -> Result<局所可視度の上書き, 起動引数エラー> {
    let 値 = 次の値を読む(引数, "--local-visibility-fixed", 起動引数エラー::局所可視性の検収指定不正)?;
    let 符号値: u8 = 値
        .trim()
        .parse()
        .map_err(|誤り| 起動引数エラー::局所可視性の検収指定不正(format!("符号値を0から255の整数として読めない({値}): {誤り}")))?;
    Ok(局所可視度の上書き::固定符号値(局所可視度の符号値::符号値から生成する(
        符号値,
    )))
}

/// 局所可視性補正の検収とフレームダンプが同時に指定されていないことを、引数を読み終えた時点で確かめる。
///
/// 排他にするのは、検収が深度画像を合成深度で丸ごと書き換えるためである。同じフレームで撮った絵は本番の
/// ジオメトリを1つも映さず、書き出しても意味を持たない。実装は検収を先に判定するため、両方を受け付けると
/// 利用者が求めたダンプが1枚も書かれないまま実行が成功して終わる。
///
/// 走査の途中でなくここで確かめるのは、指定の順序に依らず判定するためである。片方を見た時点で落とすと、
/// 先に来たほうだけが検査され、順序を入れ替えた起動が通ってしまう。
pub(in crate::cli) fn 検収とフレームダンプの排他を確かめる(
    形: Option<合成深度の形>,
    ダンプ: &super::フレームダンプ指定,
) -> Result<(), 起動引数エラー> {
    let Some(形) = 形 else { return Ok(()) };
    if !ダンプ.書き出すか() {
        return Ok(());
    }
    Err(起動引数エラー::局所可視性の検収指定不正(format!(
        "{}の検収とフレームダンプを同時に指定できない(検収は深度画像を合成深度で書き換えるため、同じフレームの絵は本番のジオメトリを映さない)",
        形.名前()
    )))
}
