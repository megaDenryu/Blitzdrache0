//! `--depth-prepass`の値から深度プリパスの方式を決める工程。受け取るのは引数の並びの残り、返すのは方式である。
//!
//! 値を1つ取る形にしたのは、3つの条件が排他だからである。フラグを2つ並べる形にすると、両方を指定した起動が
//! どちらの条件を測ったのか実行の記録から決められなくなる。
//! 値の語がASCIIなのは、CLIがプロセス境界だからである(参照: CLAUDE.md「命名」)。

use std::slice::Iter;

use blitz_render::深度プリパス方式;

use super::起動引数エラー;
use crate::error::起動エラー;

const 積まない: &str = "none";
const 色は近いか同値: &str = "near-or-equal";
const 色は等値: &str = "equal";

pub(super) fn 引数を処理する(残り: &mut Iter<String>) -> Result<深度プリパス方式, 起動エラー> {
    let Some(語) = 残り.next() else {
        return Err(深度プリパス指定の不正のエラーを組む(format!(
            "値が無い(使えるのは{積まない}と{色は近いか同値}と{色は等値}である)"
        )));
    };
    match 語.as_str() {
        積まない => Ok(深度プリパス方式::使わない),
        色は近いか同値 => Ok(深度プリパス方式::使い色は近いか同値で比べる),
        色は等値 => Ok(深度プリパス方式::使い色は等値で比べる),
        他 => Err(深度プリパス指定の不正のエラーを組む(format!(
            "知らない値({他})。使えるのは{積まない}と{色は近いか同値}と{色は等値}である"
        ))),
    }
}

fn 深度プリパス指定の不正のエラーを組む(理由: String) -> 起動エラー {
    起動引数エラー::深度プリパス方式不正(理由).into()
}
