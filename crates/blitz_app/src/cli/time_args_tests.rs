//! 時間帯に属するCLI引数の解析を検査する。既定が「世界の方針に従う」かつ「時計は停止」であることを固定する。

use super::{引数を解析する, 空の起動指定, 起動要求};

fn 描画設定を解析する(引数一覧: &[String]) -> crate::cli::起動設定 {
    match 引数を解析する(引数一覧) {
        Ok(起動要求::描画実行(設定)) => *設定,
        Ok(起動要求::天空状態報告) => panic!("描画実行の要求になるはず"),
        Err(誤り) => panic!("有効な引数は解析できるはず: {誤り}"),
    }
}

fn 語列にする(語一覧: &[&str]) -> Vec<String> {
    語一覧.iter().map(|語| (*語).to_string()).collect()
}

#[test]
fn 指定が無ければ世界の方針に従い時計は止まったままにする() {
    let 設定 = 描画設定を解析する(&[]);
    assert_eq!(設定.時間帯.空, 空の起動指定::方針に従う);
    assert!(設定.時間帯.一日内時刻の秒.is_none());
    assert!(設定.時間帯.時間倍率.is_none());
}

#[test]
fn 空の2つの上書きを別の指定として解析する() {
    assert_eq!(描画設定を解析する(&語列にする(&["--sky"])).時間帯.空, 空の起動指定::空ありとして扱う);
    assert_eq!(描画設定を解析する(&語列にする(&["--no-sky"])).時間帯.空, 空の起動指定::空を描かない);
}

#[test]
fn 一日内時刻と時間倍率を解析する() {
    let 設定 = 描画設定を解析する(&語列にする(&["--time-of-day", "43200", "--time-scale", "60"]));
    assert_eq!(設定.時間帯.一日内時刻の秒, Some(43_200.0));
    assert_eq!(設定.時間帯.時間倍率.map(|倍率| 倍率.値()), Some(60.0));
}

#[test]
fn 負の一日内時刻と負の時間倍率を拒否する() {
    assert!(引数を解析する(&語列にする(&["--time-of-day", "-1"])).is_err());
    assert!(引数を解析する(&語列にする(&["--time-scale", "-1"])).is_err());
}
