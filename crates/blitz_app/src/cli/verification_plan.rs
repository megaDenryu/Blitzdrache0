//! シーン名でも粒子でもなく起動指定が直に選ぶ検証計画の枝。担うのは「どの自己操作の並びを踏むか」だけであり、
//! 合否の判定は1つも持たない(どの枝もピクセル判定を持たず、検収側のxtaskが読み戻し画像と標準出力で判定する)。
//!
//! 真偽値を枝ごとに並べず1つの判別共用体にするのは、2つ以上が同時に立った状態が意味を持たないためである。
//! 起動指定が後に来た枝で上書きされるため、最後に書いた指定がそのまま選択になる。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 検証計画指定 {
    /// 起動指定が無いとき。シーン名・粒子・布から計画を選ぶ既定の経路へ進む。
    指定なし,
    /// `--window-rebuild`。ポスト処理を有効に保ったままリサイズ・最小化・復帰を踏む。
    ウィンドウ再構築,
    /// `--shader-reload`。差し替え前の絵を採り、監視先のシェーダーを書き換え、差し替え後の絵を最終フレームで採る。
    シェーダー差し替え,
}
