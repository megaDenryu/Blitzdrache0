//! 報告だけを求める引数の選び方を固定する。担うのは、2つ以上を同時に指定した起動がCLIに書いた順に依らず
//! 同じ要求になることと、指定が無い起動が描画実行になることである。
//!
//! 逆順の対を置くのは、書いた順の先頭を選ぶ実装ではこの2つが別の要求になるためである。片方だけを検査すると、
//! どちらの実装も通ってしまう。同じ引数の並びを2度使わずに順序だけ入れ替えるのは、選ぶ順そのものが検査の
//! 対象だからである。

use super::{引数を解析する, 起動要求};

fn 要求を得る(引数一覧: &[String]) -> 起動要求 {
    match 引数を解析する(引数一覧) {
        Ok(要求) => 要求,
        Err(誤り) => panic!("報告だけの引数は解析できるはず: {誤り}"),
    }
}

fn 語(引数一覧: [&str; 2]) -> [String; 2] {
    [引数一覧[0].to_string(), 引数一覧[1].to_string()]
}

/// 天空状態は一覧の先頭にあるため、他の報告と重ねてもどちらの順でも選ばれる。
#[test]
fn 天空状態は書いた順に依らず選ばれる() {
    let 正順 = 語(["--report-sky-state", "--report-derived-environment"]);
    let 逆順 = 語(["--report-derived-environment", "--report-sky-state"]);
    assert_eq!(要求を得る(&正順).呼び名(), 起動要求::天空状態報告.呼び名());
    assert_eq!(要求を得る(&逆順).呼び名(), 起動要求::天空状態報告.呼び名());
}

/// 一覧の中ほどどうしを重ねた対でも順序に依らない。先頭の1つだけを検査すると、書いた順の先頭を選ぶ実装が
/// 「先頭の引数がたまたま一覧の先頭でもあった」ために通ってしまう。
#[test]
fn 大気のベイク済み画像は遠方環境より先に選ばれる() {
    let 正順 = 語(["--report-atmosphere-lut", "--report-distant-environment"]);
    let 逆順 = 語(["--report-distant-environment", "--report-atmosphere-lut"]);
    let 期待 = 起動要求::大気のベイク済み画像報告.呼び名();
    assert_eq!(要求を得る(&正順).呼び名(), 期待);
    assert_eq!(要求を得る(&逆順).呼び名(), 期待);
}

/// 一覧の末尾の2つでも同じ順序が働く。
#[test]
fn 派生表現は太陽天頂区間の跨ぎより先に選ばれる() {
    let 正順 = 語(["--report-derived-environment", "--report-sun-zenith-crossings"]);
    let 逆順 = 語(["--report-sun-zenith-crossings", "--report-derived-environment"]);
    let 期待 = 起動要求::派生表現報告.呼び名();
    assert_eq!(要求を得る(&正順).呼び名(), 期待);
    assert_eq!(要求を得る(&逆順).呼び名(), 期待);
}

/// 報告だけの引数が1つも無ければ描画実行になる。この対が無いと、常に何かの報告を返す実装でも上の検査が通る。
#[test]
fn 報告だけの引数が無ければ描画実行になる() {
    let 引数 = ["--scene".to_string(), "quad".to_string()];
    assert!(matches!(要求を得る(&引数), 起動要求::描画実行(_)));
}
