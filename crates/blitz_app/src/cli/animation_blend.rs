//! アニメーションクリップ2本を混ぜる割合(判断45)。担当するのは、0から1の割合だけを受け取ることと、
//! 開発UIのスライダーが動かせる範囲を自分で決めることである。
//!
//! 裸の`f32`で持たないのは、割合と時刻(秒)と倍率がどれも`f32`の姿で同じ経路を流れるためである。
//! 0から1の割合を1から100の百分率と取り違えても計算は成立し、姿勢が黙って片方のクリップへ張り付く。

use std::ops::RangeInclusive;

use blitz_engine::animation::姿勢のブレンド係数;
use thiserror::Error;

/// ブレンド係数が受け取れない値だったこと。
#[derive(Debug, Error)]
pub(crate) enum ブレンド係数エラー {
    #[error("0から1の範囲でない: {実測}")]
    範囲の外 { 実測: f32 },
}

/// 2本目のクリップの混ざる割合。0で1本目だけ、1で2本目だけになる。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub(crate) struct アニメーションのブレンド係数(f32);

const スライダーの下限: f32 = 0.0;
const スライダーの上限: f32 = 1.0;

impl アニメーションのブレンド係数 {
    pub(crate) fn 生成する(値: f32) -> Result<Self, ブレンド係数エラー> {
        if !(スライダーの下限..=スライダーの上限).contains(&値) {
            return Err(ブレンド係数エラー::範囲の外 { 実測: 値 });
        }
        Ok(Self(値))
    }

    /// 起動指定が無いときの割合。1本目のクリップだけを使う。
    pub(crate) fn 既定() -> Self {
        Self(スライダーの下限)
    }

    /// 2本目のクリップが1画素も混ざらないか。混ざらない割合では2本目の姿勢を評価しない。
    pub(crate) fn 二本目が混ざらないか(self) -> bool {
        self.0 <= スライダーの下限
    }

    /// blitz_engineの混ぜる計算へ渡す割合。この型の受理範囲が姿勢のブレンド係数の受理範囲と同じであるため、
    /// この変換は失敗しない。破れたら不変条件の違反であり、到達したらバグとしてpanicさせる。
    pub(crate) fn 姿勢のブレンド係数へ写す(self) -> 姿勢のブレンド係数 {
        姿勢のブレンド係数::生成する(self.0).unwrap_or_else(|誤り| panic!("0から1の割合を姿勢のブレンド係数へ写せなかった(不変条件違反): {誤り}"))
    }

    /// 開発UIのスライダーが直に書き換える生値。eguiが`&mut f32`しか受けないための境界である。
    pub(crate) fn スライダーへ貸す(&mut self) -> &mut f32 {
        &mut self.0
    }

    pub(crate) fn スライダーの範囲() -> RangeInclusive<f32> {
        スライダーの下限..=スライダーの上限
    }
}
