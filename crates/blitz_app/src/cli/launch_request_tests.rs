//! 描画しない報告の要求が、他の引数より先に選ばれることを検証する。

use super::{引数を解析する, 起動要求};

#[test]
fn 天空状態報告の指定は報告の要求になる() {
    let 引数一覧 = ["--report-sky-state".to_string()];
    assert!(matches!(引数を解析する(&引数一覧), Ok(起動要求::天空状態報告)));
}

/// 報告は描画の設定を1つも読まない。描画向けの引数が一緒に並んでも報告の要求のままであることを固定する。
#[test]
fn 描画向けの引数が並んでも報告の要求になる() {
    let 引数一覧 = ["--frames".to_string(), "60".to_string(), "--report-sky-state".to_string()];
    assert!(matches!(引数を解析する(&引数一覧), Ok(起動要求::天空状態報告)));
}

#[test]
fn 指定が無ければ描画実行の要求になる() {
    assert!(matches!(引数を解析する(&[]), Ok(起動要求::描画実行(_))));
}
