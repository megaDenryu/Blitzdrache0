//! 影を落とす灯の件数の起動指定の解析と、宣言の順番への写しの反証。

#![allow(clippy::unwrap_used)]

use super::{引数を処理する, 影を落とす灯の件数の起動指定};

fn 解析する(値: &str) -> Result<影を落とす灯の件数の起動指定, String> {
    let 引数 = [値.to_owned()];
    引数を処理する(&mut 引数.iter()).map_err(|誤り| 誤り.to_string())
}

#[test]
fn 上限までの件数を受ける() {
    for 件数 in 0..=blitz_render::point_light_shadow::影を持てる灯の上限件数 {
        assert_eq!(解析する(&件数.to_string()).unwrap(), 影を落とす灯の件数の起動指定::件数を上書きする(件数));
    }
}

/// 上限を超えた件数は解析の時点で失敗させる。レンダラーの奥まで運ぶと、直すべき場所が引数であることが読めない。
#[test]
fn 上限を超えた件数は解析で失敗する() {
    let 超過 = blitz_render::point_light_shadow::影を持てる灯の上限件数 + 1;
    assert!(解析する(&超過.to_string()).is_err());
}

#[test]
fn 数値でない値は解析で失敗する() {
    assert!(解析する("いくつか").is_err());
}

/// 世界の宣言に従うときは、世界が渡した既定の件数までが影を落とす。
#[test]
fn 世界の宣言に従うときは既定の件数までが影を落とす() {
    let 指定 = 影を落とす灯の件数の起動指定::世界の宣言に従う;
    assert!(指定.宣言の順番が影を落とすか(0, 1));
    assert!(!指定.宣言の順番が影を落とすか(1, 1));
}

/// 上書きした件数は世界の既定を無視する。
#[test]
fn 上書きした件数は世界の既定を無視する() {
    let 指定 = 影を落とす灯の件数の起動指定::件数を上書きする(2);
    assert!(指定.宣言の順番が影を落とすか(1, 0));
    assert!(!指定.宣言の順番が影を落とすか(2, 4));
}
