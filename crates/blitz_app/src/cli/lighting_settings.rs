//! 世界が宣言したライティングへの、起動側からの上書きの一式。担当するのは「この実行が世界の宣言のどこを差し替えるか」だけであり、
//! 何をどこへ置くかという宣言そのものは世界の側(`crate::app::scene_lighting`)が持つ。
//!
//! 1つに束ねるのは、2つとも世界の宣言を起動指定で差し替える軸であり、起動設定の平らな並びへ別々に置くと
//! 「その実行の状態」と「世界の宣言への上書き」の区別が薄れるためである。

use super::{局所光の件数の起動指定, 影を落とす灯の件数の起動指定};

/// 世界が宣言したライティングへの起動側からの上書き一式。
///
/// - `局所光の件数`と`影を落とす灯の件数`はどちらも、これを読む世界は夜と屋内の2つの多光源の検収世界だけであり、読まない世界へ指定すると起動が型付きの失敗になる。
pub(crate) struct ライティング起動設定 {
    pub(crate) 有効: bool,                                       // --unlit指定でfalse。既定はtrue(PBRライティング有効、判断26)
    pub(crate) 局所光の件数: 局所光の件数の起動指定,             // --local-light-count <件数>。既定は世界の宣言に従う
    pub(crate) 影を落とす灯の件数: 影を落とす灯の件数の起動指定, // --point-light-shadow-count <件数>。既定は世界の宣言に従う
}

impl ライティング起動設定 {
    pub(super) fn 既定値() -> Self {
        Self {
            有効: true,
            局所光の件数: 局所光の件数の起動指定::世界の宣言に従う,
            影を落とす灯の件数: 影を落とす灯の件数の起動指定::世界の宣言に従う,
        }
    }
}
