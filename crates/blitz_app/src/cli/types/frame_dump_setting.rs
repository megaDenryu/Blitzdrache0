//! フレームダンプの指定。担うのは「どのフレームの、どの画像を、どのベース名で書き出すか」のうち画像の別とベース名である。
//!
//! 画像の別を判別共用体で持つのは、提示画像と明るさの圧縮前のHDR中間画像で外部形式も画素の意味も違うためである。
//! 提示画像は明るさの圧縮とsRGB符号化を通った後の8ビット値であり、そこから圧縮前の放射輝度は復元できない。
//! ベース名だけを持つ1つの型にして別を真偽値で添えると、書き出し側がどちらの形式で書くかを型から読めなくなる。

use std::path::{Path, PathBuf};

/// フレームダンプで書き出す画像の別とベース名。
#[derive(Debug, Clone)]
pub(crate) enum フレームダンプ指定 {
    /// 提示画像を`<ベース名>.raw`(RGBA8連結)と`<ベース名>.size`(幅 高さ)へ書き出す。
    提示画像を書き出す { 基準名: PathBuf },
    /// 明るさの圧縮前のHDR中間画像を`<ベース名>.hdr32`(RGBA単精度リトルエンディアン連結)と`<ベース名>.size`(幅 高さ)へ書き出す。
    圧縮前のHDRを書き出す { 基準名: PathBuf },
}

impl フレームダンプ指定 {
    /// 引数名から書き出す画像を選ぶ。対応をこの型が持つのは外部形式を決めるのがこの型であり、解析側に置くと形式の台帳が2箇所になるためである。
    pub(crate) fn 引数名から選ぶ(引数名: &str, 基準名: PathBuf) -> Option<Self> {
        match 引数名 {
            "--dump-frame" => Some(Self::提示画像を書き出す { 基準名 }),
            "--dump-hdr-frame" => Some(Self::圧縮前のHDRを書き出す { 基準名 }),
            _ => None,
        }
    }

    pub(crate) fn 基準名(&self) -> &Path {
        match self {
            Self::提示画像を書き出す { 基準名 } | Self::圧縮前のHDRを書き出す { 基準名 } => 基準名,
        }
    }
}
