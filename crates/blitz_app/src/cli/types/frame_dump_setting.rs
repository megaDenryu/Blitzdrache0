//! フレームダンプの指定。担うのは「どの画像をどのベース名で書き出すか」と、その指定が1回の起動に多くて1つであることである。
//!
//! 画像の別を判別共用体で持つのは、提示画像と明るさの圧縮前のHDR中間画像で外部形式も画素の意味も違うためである。
//! 提示画像は明るさの圧縮とsRGB符号化を通った後の8ビット値であり、そこから圧縮前の放射輝度は復元できない。
//! ベース名だけを持つ1つの型にして別を真偽値で添えると、書き出し側がどちらの形式で書くかを型から読めなくなる。
//!
//! 「指定なし」を`Option`でなくこの共用体の枝にするのは、指定が1つだけであるという条件をこの型の内側で閉じるためである。
//! 外に`Option`で持つと、2つ目の指定が来たときに黙って上書きする経路が呼び出し側の数だけ生まれる。

use std::path::PathBuf;

use crate::cli::{起動モード, 起動引数エラー};

/// フレームダンプで書き出す画像の別とベース名。1回の起動で選べるのは多くて1つである。
#[derive(Debug, Clone)]
pub(crate) enum フレームダンプ指定 {
    /// フレームダンプを行わない。
    指定なし,
    /// 提示画像を`<ベース名>.raw`(RGBA8連結)と`<ベース名>.size`(幅 高さ)へ書き出す。
    提示画像を書き出す { 基準名: PathBuf },
    /// 明るさの圧縮前のHDR中間画像を`<ベース名>.hdr32`(RGBA単精度リトルエンディアン連結)と`<ベース名>.size`(幅 高さ)へ書き出す。
    圧縮前のHDRを書き出す { 基準名: PathBuf },
}

/// 段差の走査が書き出し先を持つことを、引数を読み終えた時点で確かめる。
///
/// 走査の側でなくここが確かめるのは、指定の順序に依らず全部の引数を読み終えて初めて判定できるためである。
/// 持たないまま走らせると、撮影のフレームが読み戻しを1つも行わずに実行が成功して終わり、
/// 絵が1枚も残らなかったことを検収が「跨ぎのファイルが無い」という遠い失敗で知ることになる。
///
/// どちらの画像かをここで狭めないのは、段差を測る実行が圧縮前のHDRを、絵を見る実行が提示画像を要るためである。
pub(in crate::cli) fn 走査の書き出し先を確かめる(
    モード: 起動モード, 指定: &フレームダンプ指定
) -> Result<(), 起動引数エラー> {
    let 起動モード::段差走査実行 { .. } = モード else {
        return Ok(());
    };
    if 指定.書き出すか() {
        return Ok(());
    }
    Err(起動引数エラー::段差走査範囲不正(
        "段差の走査には--dump-hdr-frameか--dump-frameが要る(書き出し先が無いと絵が1枚も残らない)".to_string(),
    ))
}

impl フレームダンプ指定 {
    /// 引数名と値から指定を決める。既に別の指定があれば型付きエラーを返す。
    ///
    /// 後から来た指定で黙って上書きしないのは、1回の起動で読み戻せる画像が1枚だけだからである。
    /// 上書きを許すと、利用者が提示画像を求めたのにHDRだけが書かれた実行が成功として終わる。
    pub(crate) fn 引数から設定する(&mut self, 引数名: &str, 基準名: PathBuf) -> Result<(), 起動引数エラー> {
        if let Some(呼び名) = self.選ばれた画像の呼び名() {
            return Err(起動引数エラー::フレームダンプ不正(format!(
                "{呼び名}のフレームダンプが既に指定されているため{引数名}を受け付けられない(1回の起動で読み戻せる画像は1枚である)"
            )));
        }
        *self = match 引数名 {
            "--dump-frame" => Self::提示画像を書き出す { 基準名 },
            "--dump-hdr-frame" => Self::圧縮前のHDRを書き出す { 基準名 },
            _ => {
                return Err(起動引数エラー::フレームダンプ不正(
                    format!("{引数名}はフレームダンプの引数名ではない"),
                ));
            }
        };
        Ok(())
    }

    /// フレームダンプを行う指定があるか。
    pub(crate) fn 書き出すか(&self) -> bool {
        self.選ばれた画像の呼び名().is_some()
    }

    /// 既に選ばれている画像の呼び名。引数名でなく画像の呼び名を返すのは、同じ画像を選ぶ引数名が将来増えても意味が変わらないためである。
    fn 選ばれた画像の呼び名(&self) -> Option<&'static str> {
        match self {
            Self::指定なし => None,
            Self::提示画像を書き出す { .. } => Some("提示画像"),
            Self::圧縮前のHDRを書き出す { .. } => Some("圧縮前のHDR"),
        }
    }
}
