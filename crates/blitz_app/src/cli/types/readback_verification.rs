//! 読み戻した画像に対する照合の起動指定。担うのは「どの照合をどの材料で行うか」だけであり、
//! 読み戻しそのもの(`--dump-frame`)の指定は持たない。どの照合もダンプ対象フレームの画像を読むため、
//! `--dump-frame`と併せて指定する。
//!
//! 2つを1つに束ねるのは、どちらもダンプ対象フレームの画像を読んでCPU正本と突き合わせる指定であり、
//! 起動設定の平らな並びへ別々に置くと「状態」と「起動時の選択」の区別が薄れるためである。

use super::画面画素位置;
use crate::reports::indirect_probe::遠方環境の検収条件;

pub(crate) struct 読み戻し検収起動設定 {
    /// `--report-sky-pixel <横,縦;...>`指定で、その画素について空の色をCPU正本で求め直し、読み戻した画素と並べて出す。
    /// 既定は空の一覧(報告しない)。
    pub(crate) 空の代表画素: Vec<画面画素位置>,
    /// `--indirect-probe <条件>`指定で、遠方環境の派生表現へ解析入力を注入し、板ごとの期待と実測を並べて出す。
    /// 指定が無い実行は注入も報告も行わず、間接照明は大気から焼いた遠方環境のままである。
    pub(crate) 遠方環境の検収条件: Option<遠方環境の検収条件>,
}

impl 読み戻し検収起動設定 {
    pub(super) fn 既定値() -> Self {
        Self {
            空の代表画素: Vec::new(),
            遠方環境の検収条件: None,
        }
    }
}
