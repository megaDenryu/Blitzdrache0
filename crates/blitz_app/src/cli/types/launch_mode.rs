//! 起動時に指定できる実行モード。担うのは「そのプロセスが何フレームで終わるか」と「自己操作とピクセル判定を行うか」の別だけである。
//!
//! 起動設定の並びから分けて置くのは、この別が設定の1項目ではなく実行そのものの終わり方を決めるためである。

use crate::app::time_of_day::段差走査の指定;

/// 起動時に指定できる実行モード。
#[derive(Debug, Clone, Copy)]
pub(crate) enum 起動モード {
    /// ユーザーが閉じるまで無期限に実行する。
    無期限実行,
    /// 指定フレーム数を描画したら自動終了する(DoDのスモーク検証用)。
    スモーク実行 { フレーム数: u32 },
    /// 自己操作やピクセル判定を行わず、指定フレーム数を描画して計測する。
    ベンチ実行 { フレーム数: u32 },
    /// 遠方環境の更新を間引く区間の境界を跨ぐ瞬間ごとに、区間だけを差し替えた対の絵を撮って終わる。
    /// 終わるフレーム数は指定が持つ撮影の数から決まる。
    段差走査実行 { 走査指定: 段差走査の指定 },
}
