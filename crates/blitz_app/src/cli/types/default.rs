//! 引数を1つも受け取らなかったときの起動設定。既定値を別ファイルへ置くのは、設定の形を読む局面と
//! 「指定が無いとき何が起きるか」を読む局面が別であり、後者だけを見たい読み手が全フィールドの説明を追わずに済むためである。

use std::path::PathBuf;

use super::{布モード, 描画対象の並べ方, 粒子表示モード, 起動モード, 起動設定};
use crate::cli::{ストリーミング起動設定, 平行移動起動設定, 時間帯起動設定};

const 既定シェーダー監視パス: &str = "shaders/scene.slang";
const 既定シーン名: &str = "quad";
const 既定アセットルート: &str = "target/runtime_assets";

impl 起動設定 {
    pub(in crate::cli) fn 既定値() -> Self {
        Self {
            モード: 起動モード::無期限実行,
            シェーダー監視パス: PathBuf::from(既定シェーダー監視パス),
            シーン名: 既定シーン名.to_string(),
            アセットルート: PathBuf::from(既定アセットルート),
            描画対象の並べ方: 描画対象の並べ方::そのまま読む(),
            ライティング有効: true,
            粒子表示: 粒子表示モード::なし,
            gpu時間報告: false,
            大気のベイク済み画像パス数報告: false,
            フレーム時間報告: false,
            gpuメモリ報告: false,
            描画発行報告: false,
            インスタンス区間報告: false,
            インスタンス可視判定有効: true,
            インスタンス段選択有効: true,
            個体詳細段探査刻み: None,
            開発ui初期有効: false,
            距離区分の可視化: false,
            フレームダンプ先: None,
            空の代表画素報告: Vec::new(),
            時間帯: 時間帯起動設定::既定値(),
            ポスト処理有効: true,
            露出: 1.0,
            ブレンド: 0.0,
            布モード: 布モード::なし,
            実表示時間報告: false,
            ウィンドウ再構築検証有効: false,
            ストリーミング: ストリーミング起動設定::既定値(),
            平行移動: 平行移動起動設定::既定値(),
        }
    }
}
