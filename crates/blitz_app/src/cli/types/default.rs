//! 引数を1つも受け取らなかったときの起動設定。既定値を別ファイルへ置くのは、設定の形を読む局面と
//! 「指定が無いとき何が起きるか」を読む局面が別であり、後者だけを見たい読み手が全フィールドの説明を追わずに済むためである。

use super::{フレームダンプ指定, 布モード, 描画対象の並べ方, 粒子表示モード, 起動モード, 起動設定};
use crate::cli::{
    シャドウ計測起動設定, ストリーミング起動設定, 平行移動起動設定, 時間帯起動設定, 検証計画指定
};

const 既定のシェーダーの入口ファイル: &str = "shaders/scene.slang";
const 既定のアセットの置き場: &str = "target/runtime_assets";

impl 起動設定 {
    pub(in crate::cli) fn 既定値() -> Self {
        Self {
            モード: 起動モード::無期限実行,
            シェーダーの入口ファイル: crate::hot_reload::監視するシェーダーの入口ファイル::綴りから生成する(
                既定のシェーダーの入口ファイル,
            ),
            シーン: crate::cli::起動時シーン::既定(),
            アセットの置き場: crate::runtime_assets::実行時アセットの置き場::綴りから生成する(既定のアセットの置き場),
            描画対象の並べ方: 描画対象の並べ方::そのまま読む(),
            ライティング: super::super::lighting_settings::ライティング起動設定::既定値(),
            粒子表示: 粒子表示モード::なし,
            gpu時間報告: false,
            gpu時間のフレーム別生値報告: false,
            大気のベイク済み画像パス数報告: false,
            フレーム時間報告: false,
            gpuメモリ報告: false,
            描画発行報告: false,
            太陽角度報告: false,
            キャスター距離分布報告: false,
            インスタンス区間報告: false,
            インスタンス可視判定有効: true,
            インスタンス段選択有効: true,
            インスタンス影キャスター有効: true,
            影キャスター全体有効: true,
            個体詳細段探査刻み: None,
            開発ui初期有効: false,
            画素診断: blitz_render::cascade::画素診断::出さない,
            フレームダンプ先: フレームダンプ指定::指定なし,
            深度プリパス方式: None,
            局所可視性: crate::cli::local_visibility_settings::局所可視性の起動指定::既定値(),
            時間再構成: crate::cli::temporal_reconstruction_settings::時間再構成方式の起動上書き::既定値(),
            読み戻し検収: super::読み戻し検収起動設定::既定値(),
            時間帯: 時間帯起動設定::既定値(),
            シャドウ計測: シャドウ計測起動設定::既定値(),
            ポスト処理有効: true,
            露出: 1.0,
            ブレンド: 0.0,
            布モード: 布モード::なし,
            実表示時間報告: false,
            検証計画: 検証計画指定::指定なし,
            ストリーミング: ストリーミング起動設定::既定値(),
            平行移動: 平行移動起動設定::既定値(),
            遊ぶゲーム: crate::cli::遊ぶゲームの指定::ゲームを遊ばない,
        }
    }
}
