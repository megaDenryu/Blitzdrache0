//! 多段シャドウの費用を測るための起動指定と、その引数の解析。
//! 触れる引数は`--shadow-resolution`・`--caster-margin`・`--max-shadow-distance`・`--shadow-caster-range`の4つであり、
//! 既定値は本番の多段設定と同じ値を指す。
//!
//! この一群を計測専用と呼ぶのは、指定を1つも与えない実行が既定の多段設定と1ビットも違わないからである。
//! シャドウマップの一辺は本番ではコンパイル時に決まっていた値であり、律速の切り分け(距離区分ごとの費用が
//! ラスタライズ画素と添付処理の量に支配されるのか頂点処理量に支配されるのか)は、この1軸を振らないと測れない。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」

use std::slice::Iter;

use blitz_engine::影の視距離;
use blitz_math::メートル;
use blitz_render::cascade::影の一辺解像度;

use super::value_args::次の値を読む;
use super::起動引数エラー;

pub(crate) struct シャドウ計測起動設定 {
    /// `--shadow-resolution <テクセル数>`で選ぶシャドウマップの一辺。既定は本番と同じ2048である。
    pub(crate) 一辺解像度: 影の一辺解像度,
    /// `--caster-margin <メートル>`で選ぶキャスター余白。`None`なら世界の多段設定の余白のままである。
    /// 余白は正射影のZ範囲へ入って距離区分の光空間直方体の区間を延ばすため、縮めるとカリング候補が直接減る。
    pub(crate) キャスター余白: Option<メートル>,
    /// `--max-shadow-distance <メートル>`で選ぶ最大影距離。`None`なら世界の方針の距離のままである。
    /// この値は距離区分3の候補数だけでなく4区分の分割深度・正射影幅・世界メートル毎テクセルをすべて変え、
    /// 受影可能な最遠距離そのものを縮める(段S2-1の品質方針αの計測)。
    pub(crate) 最大影距離: Option<メートル>,
    /// `--shadow-caster-range <メートル>`で選ぶ影の視距離。`None`なら切断を1回も評価しない(段S2-1の品質方針βの計測)。
    pub(crate) 影の視距離: Option<影の視距離>,
}

impl シャドウ計測起動設定 {
    pub(crate) fn 既定値() -> Self {
        Self {
            一辺解像度: 影の一辺解像度::既定(),
            キャスター余白: None,
            最大影距離: None,
            影の視距離: None,
        }
    }
}

/// `--shadow-resolution <テクセル数>`の値を読む。2の冪と範囲の検証は値オブジェクトが持つため、ここは数の解釈だけを行う。
pub(super) fn shadow_resolution引数を処理する(引数: &mut Iter<String>) -> Result<影の一辺解像度, 起動引数エラー> {
    let 値 = 次の値を読む(引数, "--shadow-resolution", 起動引数エラー::影の一辺解像度不正)?;
    let テクセル数 = 値.parse::<u32>().map_err(|_| 起動引数エラー::影の一辺解像度不正(値.clone()))?;
    影の一辺解像度::生成する(テクセル数).map_err(|誤り| 起動引数エラー::影の一辺解像度不正(format!("{値}: {誤り}")))
}

/// `--max-shadow-distance <メートル>`の値を読む。正の有限であることは多段設定の`最大影距離を差し替える`が不変条件として持つが、
/// 起動指定は外から来る値であるため、境界であるここで拒んで型付きエラーにする(中で拒むと回復可能な入力の誤りが停止になる)。
pub(super) fn max_shadow_distance引数を処理する(引数: &mut Iter<String>) -> Result<メートル, 起動引数エラー> {
    let 値 = 次の値を読む(引数, "--max-shadow-distance", 起動引数エラー::最大影距離不正)?;
    let 長さ = 値.parse::<f32>().map_err(|_| 起動引数エラー::最大影距離不正(値.clone()))?;
    if !長さ.is_finite() || 長さ <= 0.0 {
        return Err(起動引数エラー::最大影距離不正(format!("有限かつ正でない: {値}")));
    }
    Ok(メートル::生成する(長さ))
}

/// `--shadow-caster-range <メートル>`の値を読む。正の有限であることは値オブジェクトが検証するため、ここは数の解釈と語の翻訳だけを行う。
pub(super) fn shadow_caster_range引数を処理する(引数: &mut Iter<String>) -> Result<影の視距離, 起動引数エラー> {
    let 値 = 次の値を読む(引数, "--shadow-caster-range", 起動引数エラー::影の視距離不正)?;
    let 長さ = 値.parse::<f32>().map_err(|_| 起動引数エラー::影の視距離不正(値.clone()))?;
    影の視距離::生成する(メートル::生成する(長さ)).map_err(|誤り| 起動引数エラー::影の視距離不正(format!("{値}: {誤り}")))
}

/// `--caster-margin <メートル>`の値を読む。0を許すのは、余白の寄与そのものを消した対照を計測が要るためである。
pub(super) fn caster_margin引数を処理する(引数: &mut Iter<String>) -> Result<メートル, 起動引数エラー> {
    let 値 = 次の値を読む(引数, "--caster-margin", 起動引数エラー::キャスター余白不正)?;
    let 長さ = 値.parse::<f32>().map_err(|_| 起動引数エラー::キャスター余白不正(値.clone()))?;
    if !長さ.is_finite() || 長さ < 0.0 {
        return Err(起動引数エラー::キャスター余白不正(format!("有限かつ0以上でない: {値}")));
    }
    Ok(メートル::生成する(長さ))
}
