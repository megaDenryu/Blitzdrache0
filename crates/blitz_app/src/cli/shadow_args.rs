//! 多段シャドウの費用を測るための起動指定と、その引数の解析。
//! 触れる引数は`--shadow-resolution`だけであり、既定値は本番の多段設定と同じ値を指す。
//!
//! この一群を計測専用と呼ぶのは、指定を1つも与えない実行が既定の多段設定と1ビットも違わないからである。
//! シャドウマップの一辺は本番ではコンパイル時に決まっていた値であり、律速の切り分け(距離区分ごとの費用が
//! ラスタライズ画素と添付処理の量に支配されるのか投入頂点量に支配されるのか)は、この1軸を振らないと測れない。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」

use std::slice::Iter;

use blitz_render::cascade::影の一辺解像度;

use super::value_args::次の値を読む;
use super::起動引数エラー;

pub(crate) struct シャドウ計測起動設定 {
    /// `--shadow-resolution <テクセル数>`で選ぶシャドウマップの一辺。既定は本番と同じ2048である。
    pub(crate) 一辺解像度: 影の一辺解像度,
}

impl シャドウ計測起動設定 {
    pub(super) fn 既定値() -> Self {
        Self {
            一辺解像度: 影の一辺解像度::既定(),
        }
    }
}

/// `--shadow-resolution <テクセル数>`の値を読む。2の冪と範囲の検証は値オブジェクトが持つため、ここは数の解釈だけを行う。
pub(super) fn shadow_resolution引数を処理する(引数: &mut Iter<String>) -> Result<影の一辺解像度, 起動引数エラー> {
    let 値 = 次の値を読む(引数, "--shadow-resolution", 起動引数エラー::影の一辺解像度不正)?;
    let テクセル数 = 値.parse::<u32>().map_err(|_| 起動引数エラー::影の一辺解像度不正(値.clone()))?;
    影の一辺解像度::生成する(テクセル数).map_err(|誤り| 起動引数エラー::影の一辺解像度不正(format!("{値}: {誤り}")))
}
