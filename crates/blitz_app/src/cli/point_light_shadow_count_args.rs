//! 影を落とす灯の件数の起動指定と、その解析。担当するのは「世界が置く点光源のうち何件が立方体影を宣言するか」を
//! 起動側から振れるようにすることだけであり、どこへ何色の光を置くかは世界の宣言が持つ。
//!
//! 判別共用体で持つのは、未指定を件数0で表さないためである。未指定は「世界の宣言に従う」であって
//! 「影を1件も落とさない」ではない。件数0は`件数を上書きする(0)`として正当に宣言でき、影の有無の対照の絵を採るときに使う。
//!
//! 上限を解析の時点で拒むのは、`blitz_render::局所光源列`が上限を超える宣言を型付きの失敗にするためである。
//! 起動引数の誤りをレンダラーの奥の失敗として受け取ると、直すべき場所が引数であることが読み取れない。

#[cfg(test)]
mod point_light_shadow_count_args_tests;

use std::slice::Iter;

use super::{value_args, 起動引数エラー};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 影を落とす灯の件数の起動指定 {
    世界の宣言に従う,
    件数を上書きする(usize),
}

impl 影を落とす灯の件数の起動指定 {
    /// 宣言の順に数えた番号の灯が立方体影を宣言するか。世界の宣言に従うときは、その世界の既定を呼び出し元が渡す。
    pub(crate) fn 宣言の順番が影を落とすか(self, 順番: usize, 世界の既定の件数: usize) -> bool {
        match self {
            Self::世界の宣言に従う => 順番 < 世界の既定の件数,
            Self::件数を上書きする(件数) => 順番 < 件数,
        }
    }
}

pub(super) fn 引数を処理する(引数: &mut Iter<String>) -> Result<影を落とす灯の件数の起動指定, 起動引数エラー> {
    let 値 = value_args::次の値を読む(引数, "--point-light-shadow-count", 起動引数エラー::影を落とす灯の件数不正)?;
    let 件数 = 値.parse::<usize>().map_err(|_| 起動引数エラー::影を落とす灯の件数不正(値.clone()))?;
    if 件数 > blitz_render::point_light_shadow::影を持てる灯の上限件数 {
        return Err(起動引数エラー::影を落とす灯の件数不正(format!(
            "上限{}を超える: {件数}",
            blitz_render::point_light_shadow::影を持てる灯の上限件数
        )));
    }
    Ok(影を落とす灯の件数の起動指定::件数を上書きする(件数))
}
