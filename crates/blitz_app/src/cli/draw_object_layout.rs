//! 束へ載せる描画対象の並べ方。件数は計測のために複製する描画対象の数、走査順は束の中で並べる向きである。
//!
//! 2つを1つの型にまとめるのは、どちらも「1つの束の描画対象をどう並べるか」の指定であり、シーンをレンダラー入力へ
//! 変換する経路が常に両方を要るためである。持ち回る側は2つを別々に運ばず、この型1つを運ぶ。

use super::{描画対象の走査順, 描画対象数};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 描画対象の並べ方 {
    pub(crate) 件数: Option<描画対象数>, // --object-count指定でSome。指定があるときだけ、複製した描画対象を固定カメラ内の格子へ配置する変換を合成する
    pub(crate) 走査順: 描画対象の走査順,
}

impl 描画対象の並べ方 {
    /// 複製も並べ替えもしない読み方。チャンク束はシーンの実体をそのまま載せるため、この並べ方だけを使う。
    pub(crate) fn そのまま読む() -> Self {
        Self {
            件数: None,
            走査順: 描画対象の走査順::読込順,
        }
    }
}
