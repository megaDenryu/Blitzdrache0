//! 接頭辞で括られる3つの世界群の内訳。担当するのは、群の中で方針が分かれる世界を名指しすることだけである。
//!
//! 3つを1つのファイルへ置くのは、どれも「接頭辞で群に入り、その中の一部だけが固有の方針を持つ」という
//! 同じ形をしており、群の増減が同時に起きるためである。

/// 地形世界の内訳。空と時刻の扱いは群で共通であり、内訳で分かれるのは初期カメラと時間再構成である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 地形世界の種別 {
    /// 地形の起伏を俯瞰する本番世界。
    起点,
    /// 本番と同じ軸で描く目視見本の世界。
    目視見本,
    /// クソゲー1本目「キツネの場所巡り」を遊ぶ世界。
    場所巡り,
    /// 夜の灯りを並べた検収世界。
    夜灯り,
    /// 上のどれでもない綴りの地形世界。群で共通の方針だけを受ける。
    名前で選ばれない地形,
}

/// 小物世界の内訳。1体を原点へ置く構図が群の既定であり、内訳で分かれるのは構図と屋内の照明である。
///
/// 集落と家並みを分けるのは、写す広がりが違うためである。集落は半径30メートルの輪、家並みは一辺90メートルの区画である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 小物世界の種別 {
    /// 集落を並べた世界。
    集落,
    /// 石の小屋の屋内を見る世界。
    石の小屋の屋内,
    /// 部品を組み合わせて建てた家を並べた世界。
    部品で組んだ家の並び,
    /// 上のどれでもない綴りの小物世界。1体を原点へ置く既定の構図を受ける。
    名前で選ばれない小物,
}

/// 植生の検収世界の内訳。影の範囲は群で共通であり、内訳で分かれるのは方向光の向きだけである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 植生の検収世界の種別 {
    /// 群と一緒に床を敷いた世界。方向光をほぼ水平の-X向きにして、影が床を長く横切る配置を作る。
    床を同居させた,
    /// 床を持たない世界。方向光は既定のままである。
    床を持たない,
}
