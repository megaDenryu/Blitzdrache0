//! 起動時シーンがどの世界かの数え上げ。担当するのは枝の定義だけであり、綴りからの見分けは`parse`が、
//! 綴りとの組は親の`起動時シーン`が持つ。接頭辞で括る3つの世界群の内訳は`family`が持つ。
//!
//! 接頭辞で括られる世界を1つの枝にまとめ、その中で方針が分かれる世界だけを内側の枝で名指しする。
//! 名前で方針が分かれる場所はすべてこの数え上げの網羅`match`になるため、世界を1つ足すと、
//! 判断を求められている方針がコンパイルの失敗として現れる。

mod family;

pub(crate) use family::{地形世界の種別, 小物世界の種別, 植生の検収世界の種別};

/// 起動時に読むシーンがどの世界か。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 世界の種別 {
    /// 既定の検収世界。板を1枚だけ置き、ホットリロードの往復をこの世界で検収する。
    平面板,
    /// 標準サンプルが表示されることを検収する世界。
    ヘルメット,
    /// 床へ影が落ちることを検収する世界。
    影の検収世界,
    /// GPUスキニングのアニメーションが絵を動かすことを検収する世界。
    キツネ,
    /// 資源表世代の差し替えを1つのプロセスの中で起こす検収世界。
    材質差し替えの検収世界,
    /// 遠方環境の消費を機械判定する検収世界。金属と誘電体の板を粗さの水準ごとに並べてある。
    間接照明の検収世界,
    /// 群が両方の視錐台の外にある検収世界。シャドウパスの入力が空になる状態を作る。
    両視錐台外の群の検収世界,
    /// 2つの材質を1つの生成物へ収めた検収世界。
    二材質の検収世界,
    /// 圧縮テクスチャの読み出しを検収する世界。
    テクスチャ圧縮の検収世界,
    /// 群を1つのチャンクの中央へ敷く検収世界。
    植生の検収世界(植生の検収世界の種別),
    /// Blender生成の小物を置く世界。
    小物世界(小物世界の種別),
    /// 地形チャンクを敷く世界。空と時刻から照明を導くのはこの群だけである。
    地形世界(地形世界の種別),
    /// 上のどれでもない綴りの世界。世界ごとの方針を1つも持たず、すべて既定になる。
    名前で選ばれない世界,
}
