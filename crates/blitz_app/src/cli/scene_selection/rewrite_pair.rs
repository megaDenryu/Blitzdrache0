//! ホットリロードの検収が上書きする実行時アセットの対と、世界ごとのその選択。担当するのは、複写の元と先の
//! 安定idを1つの値へ収めて2つの取り違えを呼び出し側で書けなくすることと、どの世界がどの対を使うかを決めることである。

use blitz_engine::アセットID;

use super::parse;
use super::world_kind::世界の種別;

/// 平面板の世界へ上書きする側の生成物の綴り。板の色だけが違う生成物である。
const 平面板の差し替え元の綴り: &str = "quad_alt";
/// 材質差し替えの検収世界へ上書きする側の生成物の綴り。材質の係数だけが違う生成物である。
const 材質差し替えの差し替え元の綴り: &str = "material_reload_alt";

/// 元の綴りの生成物を先の綴りの生成物へ複写する対。
pub(crate) struct 差し替える生成物の対 {
    複写元: アセットID,
    複写先: アセットID,
}

impl 差し替える生成物の対 {
    /// 世界ごとの差し替えの対。材質差し替えの検収世界だけが自分の対を持ち、残りの世界は平面板の対を使う。
    /// アセットの書き換えを踏む計画が平面板と材質差し替えの2つしかないためである。
    pub(crate) fn 世界の種別から選ぶ(種別: 世界の種別) -> Self {
        let (複写元, 複写先) = match 種別 {
            世界の種別::材質差し替えの検収世界 => (材質差し替えの差し替え元の綴り, parse::材質差し替えの検収世界の綴り),
            世界の種別::平面板
            | 世界の種別::ヘルメット
            | 世界の種別::影の検収世界
            | 世界の種別::キツネ
            | 世界の種別::間接照明の検収世界
            | 世界の種別::両視錐台外の群の検収世界
            | 世界の種別::二材質の検収世界
            | 世界の種別::テクスチャ圧縮の検収世界
            | 世界の種別::植生の検収世界(_)
            | 世界の種別::小物世界(_)
            | 世界の種別::地形世界(_)
            | 世界の種別::名前で選ばれない世界 => (平面板の差し替え元の綴り, parse::平面板の綴り),
        };
        Self {
            複写元: 安定idへ写す(複写元),
            複写先: 安定idへ写す(複写先),
        }
    }

    pub(crate) fn 複写元(&self) -> &アセットID {
        &self.複写元
    }

    pub(crate) fn 複写先(&self) -> &アセットID {
        &self.複写先
    }
}

/// 綴りは呼び出し側が持つ定数であり、空文字になりえない。空だった場合は定数の記述が壊れているため止める。
fn 安定idへ写す(綴り: &str) -> アセットID {
    アセットID::生成する(綴り).unwrap_or_else(|誤り| panic!("差し替える生成物の綴りの定数が不正だった({綴り}): {誤り}"))
}
