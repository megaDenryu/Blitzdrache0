//! 時間再構成の起動指定。触れる状態を持たず、担うのは世界の宣言を上書きする1つの軸だけである。
//!
//! 切れる形を残すのは、時間再構成を入れる前の絵と後の絵を同じ実行条件で比べるためであり、バイト一致に依存する
//! 検収入口を世界の宣言を書き換えずに素の条件へ戻せるようにするためでもある
//! (`参照: _doc/設計/時間再構成.md`「判断e: 世界宣言の第4軸と検収の保護」)。

/// 時間再構成を効かせるかどうか。既定は世界の宣言に従う。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 時間再構成方式の起動上書き {
    宣言に従う,     // 既定。世界が宣言した時間再構成方式をそのまま使う
    使わないで描く, // --no-taa。世界が履歴混合を宣言していても、今のフレームの結果をそのまま出す
}

impl 時間再構成方式の起動上書き {
    pub(crate) fn 既定値() -> Self {
        Self::宣言に従う
    }
}
