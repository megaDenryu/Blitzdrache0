//! 値を伴わない時間帯の起動指定の解釈。担当するのは「引数の文字列1つを時間帯起動設定の上書きへ写し、
//! 時間帯の指定でなければその旨を返す」ことである。
//!
//! 引数の分岐の台帳から分けるのは、触る先が時間帯起動設定の4つのフィールドだけに閉じているためである。
//! 上書きの意味はそれぞれの列挙の定義にあり、ここは文字列と枝の対応だけを持つ。

use super::{太陽円盤指定, 時間帯起動設定, 空の起動指定, 空中遠近合成指定, 自動露出の起動指定};

/// 引数を反映できたら真、時間帯の指定でなければ偽を返す。
pub(super) fn 反映する(設定: &mut 時間帯起動設定, 引数値: &str) -> bool {
    match 引数値 {
        "--sky" => 設定.空 = 空の起動指定::空ありとして扱う,
        "--no-sky" => 設定.空 = 空の起動指定::空を描かない,
        "--no-auto-exposure" => 設定.自動露出 = 自動露出の起動指定::時刻別固定で描く,
        "--no-aerial-composite" => 設定.空中遠近合成 = 空中遠近合成指定::合成しない,
        "--sun-disk-off" => 設定.太陽円盤 = 太陽円盤指定::消す,
        _ => return false,
    }
    true
}
