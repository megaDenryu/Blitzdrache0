//! 開発UIが実行中に書き換える2つの量の受理範囲の検査。確かめるのは、スライダーが動かせる範囲の両端が
//! どちらも値オブジェクトの受理範囲の内側にあることと、範囲の外の値が型付きの失敗になることである。
//!
//! 両端の検査を置くのは、スライダーが生値を直に書き換える境界を持つためである。範囲が受理範囲からはみ出すと、
//! 利用者がつまみを端まで動かしただけで不変条件の破れた値が生まれる。

use super::{アニメーションのブレンド係数, 露出倍率};

#[test]
fn 露出倍率のスライダーの両端は受理範囲の内側にある() {
    let 範囲 = 露出倍率::スライダーの範囲();
    assert!(露出倍率::生成する(*範囲.start()).is_ok());
    assert!(露出倍率::生成する(*範囲.end()).is_ok());
}

#[test]
fn 露出倍率は正の有限値だけを受ける() {
    assert!(露出倍率::生成する(0.0).is_err());
    assert!(露出倍率::生成する(-1.0).is_err());
    assert!(露出倍率::生成する(f32::NAN).is_err());
    assert!(露出倍率::生成する(f32::INFINITY).is_err());
}

#[test]
fn 露出倍率は補正段を2の冪として掛ける() {
    let 倍率 = 露出倍率::既定().補正段を掛ける(2.0);
    assert!((倍率.値() - 4.0).abs() < f32::EPSILON);
}

#[test]
fn ブレンド係数のスライダーの両端は受理範囲の内側にある() {
    let 範囲 = アニメーションのブレンド係数::スライダーの範囲();
    assert!(アニメーションのブレンド係数::生成する(*範囲.start()).is_ok());
    assert!(アニメーションのブレンド係数::生成する(*範囲.end()).is_ok());
}

#[test]
fn ブレンド係数は0から1の外を受けない() {
    assert!(アニメーションのブレンド係数::生成する(-0.001).is_err());
    assert!(アニメーションのブレンド係数::生成する(1.001).is_err());
    assert!(アニメーションのブレンド係数::生成する(f32::NAN).is_err());
}

#[test]
fn 既定のブレンド係数は二本目を混ぜない() {
    assert!(アニメーションのブレンド係数::既定().二本目が混ざらないか());
    let 混ぜる = アニメーションのブレンド係数::生成する(0.5).unwrap_or_else(|誤り| panic!("0.5が受理されない: {誤り}"));
    assert!(!混ぜる.二本目が混ざらないか());
}
