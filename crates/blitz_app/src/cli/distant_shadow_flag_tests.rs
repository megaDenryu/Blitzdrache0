//! 遠景だけの影発行を切る帰属診断が、他の影キャスターを変えないことを検査する。

use super::{引数を解析する, 起動要求};

#[test]
fn 遠景影なしは遠景だけを無効にする() {
    let 結果 = 引数を解析する(&["--no-distant-shadow".to_string()]);
    let Ok(起動要求::描画実行(設定)) = 結果 else {
        panic!("遠景影なしの描画指定を解析できる必要がある");
    };
    assert!(!設定.遠景影キャスター有効);
    assert!(設定.影キャスター全体有効);
    assert!(設定.インスタンス影キャスター有効);
}
