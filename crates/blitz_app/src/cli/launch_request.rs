//! 起動時に受け取った要求。ウィンドウとレンダラーを作るかどうかがここで分かれるため、
//! 描画しない要求を起動設定のフラグにせず、要求そのものを判別共用体で表す。

use super::起動設定;

pub(crate) enum 起動要求 {
    /// ウィンドウを作って描画する通常の起動。
    描画実行(Box<起動設定>),
    /// 描画せず、代表時刻の天空状態表を標準出力へ出して終える。
    天空状態報告,
    /// ウィンドウを作らず、ウィンドウなし実行のGPUで大気のベイク済み画像を焼いて読み戻した表を標準出力へ出して終える。
    大気のベイク済み画像報告,
    /// ウィンドウを作らず、ウィンドウなし実行のGPUで遠方環境の立方体画像を焼いて読み戻した表を標準出力へ出して終える。
    遠方環境報告,
    /// ウィンドウを作らず、ウィンドウなし実行のGPUで拡散照度・鏡面畳込み・反射率積分表を焼いて読み戻した表を標準出力へ出して終える。
    派生表現報告,
    /// 描画せず、一日で太陽天頂区間の境界を跨ぐ瞬間の表を標準出力へ出して終える。
    太陽天頂区間の跨ぎ報告,
}

impl 起動要求 {
    /// 要求の種別を1語で表す名前。テストが「どの枝になったか」を落ちたときのメッセージへ出すのに使う。
    #[cfg(test)]
    pub(crate) fn 呼び名(&self) -> &'static str {
        match self {
            Self::描画実行(_) => "描画実行",
            Self::天空状態報告 => "天空状態報告",
            Self::大気のベイク済み画像報告 => "大気のベイク済み画像報告",
            Self::遠方環境報告 => "遠方環境報告",
            Self::派生表現報告 => "派生表現報告",
            Self::太陽天頂区間の跨ぎ報告 => "太陽天頂区間の跨ぎ報告",
        }
    }
}
