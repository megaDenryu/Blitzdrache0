//! 時間帯に関する起動設定。空を描くかどうかの上書きと、ゲーム時計の初期時刻・倍率を持つ。

use blitz_engine::time::{世界時刻, 時間倍率};
use blitz_math::大域秒;

/// 空に関する起動指定。既定は世界の方針に従う。
///
/// 2つの上書きが対称でないのは、それぞれが有用な意味を持つためである。`--sky`は方針そのものを空ありへ上書きし、
/// 空の絵と時刻から導くライティング・露出をまとめて入れる。`--no-sky`は空パスだけを積まないようにし、
/// ライティングと露出は方針のまま残す。空ありの世界から空の絵だけを外して既存の画素判定を保つ検収がこの形を要る。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 空の起動指定 {
    方針に従う,
    /// `--sky`。世界の方針が空なしでも空ありとして扱う。
    空ありとして扱う,
    /// `--no-sky`。空パスだけを積まない。
    空を描かない,
}

/// 空の放射輝度をどの方式で評価するか。既定はHosek-Wilkie解析近似であり、大気LUT腕は起動指定で選ぶ。
///
/// 既定を切り替えないのは、大気LUT腕の絵の検収(代表時刻の目視・画素判定)が済むまで既定の絵を動かさない
/// ためである(参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「段階導入」7c)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 空の方式指定 {
    /// 既定。`blitz_engine`が焼いた解析近似の係数を空パスが評価する。
    Hosek解析近似,
    /// `--sky-lut`。プリコンピュート大気LUTから空パスが引く。
    大気LUT,
}

/// 遠景の霞を合成するかどうか。大気LUT腕でだけ意味を持つ指定である。
///
/// 切れる形を残すのは、合成を入れる前の絵へ戻る停止点を保つためである。合成を切った絵は、ボリュームを1枚も
/// 焼かず合成パスを1本も積まない経路を通るため、空中遠近を入れる前の描画と同一である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 空中遠近合成指定 {
    /// 既定。大気LUT腕なら遠景へ霞を合成する。
    合成する,
    /// `--no-aerial-composite`。霞を1画素も乗せない。
    合成しない,
}

/// 空の絵をどう作るかの指定。方式と合成を1つにまとめるのは、どちらもシェーダーの腕の選択であり、
/// 選んだ組がそのまま`空シェーダー`の腕になるためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 空の描画指定 {
    /// 空の放射輝度の評価方式。`--sky-lut`で大気LUT腕を選ぶ。
    pub(crate) 方式: 空の方式指定,
    /// 遠景の霞の合成。`--no-aerial-composite`で切る。
    pub(crate) 空中遠近合成: 空中遠近合成指定,
}

/// 時間帯まわりの起動設定一式。
pub(crate) struct 時間帯起動設定 {
    pub(crate) 空: 空の起動指定,
    pub(crate) 空の描画: 空の描画指定,
    /// `--time-of-day <秒>`で指定した一日の始まりからの秒。既定は世界の方針が持つ既定時刻を使う。
    pub(crate) 一日内時刻の秒: Option<f64>,
    /// `--time-scale <倍率>`で指定した実時間1秒あたりの世界時間。指定が無いと時計は止まったままである。
    /// 既定を停止に置くのは、時刻の進行が読み戻し画像の決定性を壊すためである。
    pub(crate) 時間倍率: Option<時間倍率>,
}

impl 時間帯起動設定 {
    pub(super) fn 既定値() -> Self {
        Self {
            空: 空の起動指定::方針に従う,
            空の描画: 空の描画指定 {
                方式: 空の方式指定::Hosek解析近似,
                空中遠近合成: 空中遠近合成指定::合成する,
            },
            一日内時刻の秒: None,
            時間倍率: None,
        }
    }

    /// 起動指定があればその一日内秒を紀元から数えた時刻、無ければ世界の方針の既定時刻を使う。
    /// 紀元は一日の始まりであるため、指定した秒がそのまま一日内時刻になる。
    pub(crate) fn 初期時刻を決める(&self, 既定時刻: 世界時刻) -> 世界時刻 {
        let Some(秒) = self.一日内時刻の秒 else {
            return 既定時刻;
        };
        世界時刻::生成する(大域秒::生成する(秒)).unwrap_or_else(|誤り| panic!("--time-of-dayの検証済みの値から世界時刻を作れなかった: {誤り}"))
    }
}
