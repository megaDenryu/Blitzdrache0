//! 局所光の件数の起動指定と、その解析。担当するのは「世界が置く点光源の件数を起動側から振れるようにする」ことだけであり、
//! どこへ何色の光を置くかは世界の宣言(`crate::app::scene_lighting`)が持つ。
//!
//! 判別共用体で持つのは、未指定を件数0や番兵の数で表さないためである。未指定は「世界の宣言に従う」であって
//! 「光を置かない」ではない。件数0は`件数を上書きする(0)`として正当に宣言できる値であり、光を1件も持たない
//! 世界の絵を採るときに使う。
//!
//! 上限を解析の時点で拒むのは、`blitz_render::局所光源列`が上限を超える宣言を型付きの失敗にするためである。
//! 起動引数の誤りをレンダラーの奥の失敗として受け取ると、直すべき場所が引数であることが読み取れない。

use std::slice::Iter;

use super::{value_args, 起動引数エラー};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 局所光の件数の起動指定 {
    世界の宣言に従う,
    件数を上書きする(usize),
}

pub(super) fn 引数を処理する(引数: &mut Iter<String>) -> Result<局所光の件数の起動指定, 起動引数エラー> {
    let 値 = value_args::次の値を読む(引数, "--local-light-count", 起動引数エラー::局所光の件数不正)?;
    let 件数 = 値.parse::<usize>().map_err(|_| 起動引数エラー::局所光の件数不正(値.clone()))?;
    if 件数 > blitz_render::局所光源列::上限件数 {
        return Err(起動引数エラー::局所光の件数不正(format!(
            "上限{}を超える: {件数}",
            blitz_render::局所光源列::上限件数
        )));
    }
    Ok(局所光の件数の起動指定::件数を上書きする(件数))
}
