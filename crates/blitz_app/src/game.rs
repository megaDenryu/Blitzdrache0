//! コンポジションルートがゲームロジック層を配線する場所。ロジックは書かず、どのゲームを回すかの選択と、
//! 1フレームに1刻みだけ進める呼び出しの配線だけを持つ。
//!
//! 遊ばない状態を`Option`でなく枝で持つのは、`--game`の指定が無い起動でゲーム更新も操作の確定も1つも走らないことを
//! 型で保つためである。既存の入口(スモーク・ベンチ・段差走査・報告)はどれもこの枝へ落ちる。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「第1段階の定義」。

mod entity_id;
mod entity_ledger;
mod fox_tour;
mod step_seconds;
mod summary;

pub(crate) use summary::ゲーム進行の要約;

use blitz_render::frame_input::動く個体の大域位置の指定;
use blitz_render::{レンダラーエラー, 描画シーン素材, 描画束ID};

use crate::cli::{起動モード, 遊ぶゲームの指定};
use crate::input::入力状態;

/// 1刻み進めた結果、イベントループを閉じるべきかどうか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum ゲームの終了要求 {
    続ける,
    終了する,
}

/// コンポジションルートが保持するゲームの配線。
pub(crate) enum ゲーム配線 {
    /// `--game`の指定が無い起動。
    ゲームを遊ばない,
    /// クソゲー1本目を回す起動。
    キツネの場所巡り(fox_tour::キツネの場所巡りの配線),
}

impl ゲーム配線 {
    pub(crate) fn 起動設定から作る(遊ぶゲーム: 遊ぶゲームの指定, モード: 起動モード) -> Self {
        match 遊ぶゲーム {
            遊ぶゲームの指定::ゲームを遊ばない => Self::ゲームを遊ばない,
            遊ぶゲームの指定::キツネの場所巡り => {
                Self::キツネの場所巡り(fox_tour::キツネの場所巡りの配線::生成する(モード))
            }
        }
    }

    /// そのフレームのゲーム更新を1刻みだけ行う。入力状態を受け取るのは、遊ばない起動で操作の確定すら行わないためである。
    pub(crate) fn 一刻み進める(&mut self, 入力状態: &mut 入力状態) -> ゲームの終了要求 {
        let Self::キツネの場所巡り(配線) = self else {
            return ゲームの終了要求::続ける;
        };
        配線.一刻み進める(入力状態.ゲームの操作入力を確定する());
        if 配線.終了が決まったか() {
            return ゲームの終了要求::終了する;
        }
        ゲームの終了要求::続ける
    }

    /// 束の読込より前に、その束の描画シーン素材へ動く個体を宣言する。遊ばない起動では1件も宣言せず、
    /// 全描画対象が読込時に一度だけ書く静的な個体変換のままになる。
    pub(crate) fn 束の描画シーン素材へ動く個体を宣言する(
        &self,
        束id: 描画束ID,
        描画シーン: &mut 描画シーン素材,
    ) -> Result<(), レンダラーエラー> {
        let Self::キツネの場所巡り(配線) = self else {
            return Ok(());
        };
        for 宣言 in 配線.台帳().束の動く個体の宣言一覧を作る(束id) {
            描画シーン.動く個体を宣言する(宣言)?;
        }
        Ok(())
    }

    /// そのフレームの描画入力が借用する動く個体の位置の列を預ける。遊ばない起動では空の列であり、確保も書き込みも起こらない。
    pub(crate) fn 動く個体の大域位置の指定一覧を預ける(&mut self) -> Vec<動く個体の大域位置の指定> {
        match self {
            Self::ゲームを遊ばない => Vec::new(),
            Self::キツネの場所巡り(配線) => 配線.台帳を借りる().指定一覧を預ける(),
        }
    }

    pub(crate) fn 動く個体の大域位置の指定一覧を戻す(&mut self, 受け皿: Vec<動く個体の大域位置の指定>) {
        let Self::キツネの場所巡り(配線) = self else {
            return;
        };
        配線.台帳を借りる().指定一覧を戻す(受け皿);
    }

    /// 終了時の報告へ渡す要約。遊ばない起動では報告する対象が無いため`None`を返す。
    pub(crate) fn 進行の要約を作る(&self) -> Option<ゲーム進行の要約> {
        match self {
            Self::ゲームを遊ばない => None,
            Self::キツネの場所巡り(配線) => Some(配線.進行の要約を作る()),
        }
    }
}
