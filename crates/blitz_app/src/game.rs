/// 1刻み進めた結果、イベントループを閉じるべきかどうか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum ゲームの終了要求 {
    続ける,
    終了する,
}

/// コンポジションルートが保持するゲームの配線。
pub(crate) enum ゲーム配線 {
    /// `--game`の指定が無い起動。
    ゲームを遊ばない,
    /// クソゲー1本目を回す起動。
    キツネの場所巡り(fox_tour::キツネの場所巡りの配線),
    歩くだけ(walk_only::歩くだけの配線),
}

impl ゲーム配線 {
    pub(crate) fn 起動設定から作る(遊ぶゲーム: 遊ぶゲームの指定, モード: 起動モード) -> Self {
        match 遊ぶゲーム {
            遊ぶゲームの指定::ゲームを遊ばない => Self::ゲームを遊ばない,
            遊ぶゲームの指定::キツネの場所巡り(操作の出どころ) => {
                Self::キツネの場所巡り(fox_tour::キツネの場所巡りの配線::生成する(モード, 操作の出どころ))
            }
            遊ぶゲームの指定::歩くだけ => Self::歩くだけ(walk_only::歩くだけの配線::生成する(モード)),
        }
    }

    /// そのフレームのゲーム更新を1刻みだけ行う。入力状態を受け取るのは、遊ばない起動で操作の確定すら行わないためである。
    /// カメラのヨーを受け取るのは、移動をカメラの向き基準にするためである。ヨーをゲームの前へ進む向きへ写すのはこの配線であり、
    /// ゲームロジック層はカメラの型を1つも知らない。
    pub(crate) fn 一刻み進める(&mut self, 入力状態: &mut 入力状態, カメラのヨー: ラジアン) -> ゲームの終了要求 {
        match self {
            Self::ゲームを遊ばない => {}
            Self::キツネの場所巡り(配線) => {
                let 前へ進む向き = 前へ進む向きの方位角::生成する(カメラのヨー);
                配線.一刻み進める(入力状態.ゲームの操作入力を確定する(), 前へ進む向き);
                if 配線.終了が決まったか() {
                    return ゲームの終了要求::終了する;
                }
            }
            Self::歩くだけ(配線) => 配線.一刻み進める(入力状態.ゲームの操作入力を確定する(), カメラのヨー),
        }
        ゲームの終了要求::続ける
    }

    /// カタログを構築した直後に、その世界の高さ場をゲームへ据える。遊ばない起動では高さ場を1度も読まない。
    pub(crate) fn カタログから高さ場を据える(
        &mut self,
        カタログ: &blitz_engine::カタログ,
    ) -> Result<(), blitz_engine::height_field::高さ場読込エラー> {
        match self {
            Self::ゲームを遊ばない => Ok(()),
            Self::キツネの場所巡り(配線) => 配線.カタログから高さ場を据える(カタログ),
            Self::歩くだけ(配線) => 配線.カタログから高さ場を据える(カタログ),
        }
    }

    /// 終了時の報告へ渡す要約。遊ばない起動では報告する対象が無いため`None`を返す。
    pub(crate) fn 進行の要約を作る(&self) -> Option<ゲーム進行の要約> {
        match self {
            Self::ゲームを遊ばない => None,
            Self::キツネの場所巡り(配線) => Some(配線.進行の要約を作る()),
            Self::歩くだけ(_) => None,
        }
    }
}
