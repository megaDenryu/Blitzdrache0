//! quad/helmetそれぞれのフレームスケジュール。全アクションの時刻は調整可
//! (開発スレッド「判断22」)。24分割の粗い刻みを使い、ホットリロードの
//! 0.5秒ポーリング・実際の再読込/再コンパイル完了を書き換えから判定まで
//! 十分な猶予(200フレーム超)を置いて待てるようにする。

use super::スモークアクション;

/// quadステージ: 自己操作(リサイズ→最小化→復帰) → 初期色判定 →
/// アセット書き換え→反映後判定 → シェーダー書き換え→最終判定。
pub(super) fn quad計画(現在フレーム: u32, 総フレーム数: u32) -> スモークアクション {
    if 現在フレーム == 総フレーム数 / 24 {
        スモークアクション::リサイズ
    } else if 現在フレーム + 1 == 総フレーム数 * 2 / 24 {
        スモークアクション::初期色判定
    } else if 現在フレーム == 総フレーム数 * 2 / 24 {
        スモークアクション::最小化
    } else if 現在フレーム == 総フレーム数 * 3 / 24 {
        スモークアクション::復帰
    } else if 現在フレーム == 総フレーム数 * 4 / 24 {
        スモークアクション::アセット書き換え
    } else if 現在フレーム + 1 == 総フレーム数 * 15 / 24 {
        スモークアクション::アセット反映後判定
    } else if 現在フレーム == 総フレーム数 * 15 / 24 {
        スモークアクション::シェーダー書き換え
    } else if 現在フレーム + 1 == 総フレーム数 {
        スモークアクション::最終判定
    } else {
        スモークアクション::通常描画
    }
}

/// helmetステージ: 標準サンプルの表示確認のみ(最終フレームで読み戻し判定)。
pub(super) fn helmet計画(現在フレーム: u32, 総フレーム数: u32) -> スモークアクション {
    if 現在フレーム + 1 == 総フレーム数 {
        スモークアクション::ヘルメット判定
    } else {
        スモークアクション::通常描画
    }
}

/// particlesステージ: コンピュート→グラフィックスのバッファ共有が同期して動くことの
/// 実証のみ(最終フレームで読み戻し判定、判断29)。
pub(super) fn particles計画(現在フレーム: u32, 総フレーム数: u32) -> スモークアクション {
    if 現在フレーム + 1 == 総フレーム数 {
        スモークアクション::粒子判定
    } else {
        スモークアクション::通常描画
    }
}
