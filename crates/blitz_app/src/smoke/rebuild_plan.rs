//! ポスト処理を有効に保ったままウィンドウ再構築(リサイズ・最小化・復帰)を踏む検証のフレームスケジュール。
//! ピクセル判定を1つも持たないのは、明るさの圧縮後の色に既存ステージの期待色がそのまま使えないためである。
//! 合否はVulkan validationの件数と終了時のGPUメモリ残数検査で決まるため、この計画は自己操作と通常描画だけを返す。

use super::スモークアクション;

/// リサイズ→最小化→復帰を総フレーム数の1/8刻みで踏み、残りは通常描画を続ける。
/// 復帰後に総フレーム数の5/8を通常描画に充て、再構築後のスワップチェーンで描き続けられることを確かめる。
pub(crate) fn ウィンドウ再構築計画(現在フレーム: u32, 総フレーム数: u32) -> スモークアクション {
    if 現在フレーム == 総フレーム数 / 8 {
        スモークアクション::リサイズ
    } else if 現在フレーム == 総フレーム数 * 2 / 8 {
        スモークアクション::最小化
    } else if 現在フレーム == 総フレーム数 * 3 / 8 {
        スモークアクション::復帰
    } else {
        スモークアクション::通常描画
    }
}
