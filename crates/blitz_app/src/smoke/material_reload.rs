//! 資源表世代の差し替えを1つのプロセスの中で起こす検収ステージ。担当するのは、このステージに属する安定IDと、
//! フレーム番号から自己操作を決める計画である。
//!
//! 同じ形を同じプリミティブ数で塗る2つの生成物のうち、材質の係数だけが違う方を実行時アセットへ上書きする。
//! アプリはmtimeの変化を見てシーンを差し替え、材質資源表は新しい世代を1つ作って公開する。差し替えの前後を
//! 同じプロセスで読み戻すため、旧世代の画素と新世代の画素が混ざらないことを検収側が画素で判定できる。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段4bの検収ゲート(iv)

use super::スモークアクション;

/// この計画で走るシーンの安定ID。アセット宣言の`材質差し替えのシーン`と同じ綴りである。
/// 二材質の検収シーンと同じソースを別の安定IDへ焼くのは、この検収の実行中に生成物が上書きされるためであり、
/// 既存の`multi-material-draw`が読む生成物を巻き込まないためである。安定IDを`multi_material`で始めないのは、
/// 読み戻しだけの検収計画でなくこの差し替えの計画を選ばせるためである。
const シーン: &str = "material_reload";
/// 上書きする側の安定ID。アセット宣言の`材質差し替えの代替シーン`と同じ綴りである。
const 代替シーン: &str = "material_reload_alt";

pub(crate) fn このシーンか(シーン名: &str) -> bool {
    シーン名 == シーン
}

/// このシーンで走っているときだけ、書き換えの元と先の安定IDの対を返す。
pub(crate) fn 書き換える対(シーン名: &str) -> Option<(&'static str, &'static str)> {
    このシーンか(シーン名).then_some((代替シーン, シーン))
}

/// 差し替え前の絵を読み戻して保存する → 実行時アセットを上書きする → 反映後の絵を最終フレームの読み戻しで採る。
/// 書き換えから最終フレームまでを総フレーム数の7割以上空けるのは、ホットリロードの0.5秒ごとの確認と、
/// 再読込・世代の作り直し・次の描画までを十分な猶予で待つためである。
pub(crate) fn 計画(現在フレーム: u32, 総フレーム数: u32) -> スモークアクション {
    if 現在フレーム + 1 == 総フレーム数 * 2 / 24 {
        スモークアクション::差し替え前ダンプ
    } else if 現在フレーム == 総フレーム数 * 3 / 24 {
        スモークアクション::アセット書き換え
    } else {
        スモークアクション::通常描画
    }
}
