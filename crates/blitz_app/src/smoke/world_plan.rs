//! 世界の種別からフレームスケジュールを選ぶ工程。受け取るのは世界の種別とフレーム番号、返すのはそのフレームの
//! 自己操作である。粒子・布・開発UI・描画対象数から選ぶ計画は世界の名前を見ないため、親の`判定する`が先に決める。
//!
//! 網羅`match`で書くのは、検収の世界を1つ足したときに、その世界がどの計画で走るのかを書き手に必ず決めさせるためである。
//! 既定の計画は平面板のホットリロード検証であり、監視対象のシェーダーと平面板の実行時形式を書き換えるため、
//! 新しい検収世界をここへ落とすとリポジトリのシェーダーと既存の生成物が書き換わる。

use super::{material_reload, plan, スモークアクション};
use crate::cli::{世界の種別, 地形世界の種別};

pub(super) fn 世界ごとの動作を導出する(
    現在フレーム: u32, 総フレーム数: u32, 種別: 世界の種別
) -> スモークアクション {
    match 種別 {
        世界の種別::材質差し替えの検収世界 => {
            material_reload::現在フレームから材質差し替えの動作を導出する(現在フレーム, 総フレーム数)
        }
        世界の種別::ヘルメット => plan::現在フレームからヘルメットの動作を導出する(現在フレーム, 総フレーム数),
        世界の種別::影の検収世界 => plan::現在フレームからシャドウの動作を導出する(現在フレーム, 総フレーム数),
        世界の種別::キツネ => plan::現在フレームからフォックスの動作を導出する(現在フレーム),
        // 書き換えも画素判定も持たず、絵の合否を検収側のxtaskが読み戻し画像と計数で決める世界。
        世界の種別::植生の検収世界(_)
        | 世界の種別::小物世界(_)
        | 世界の種別::二材質の検収世界
        | 世界の種別::テクスチャ圧縮の検収世界
        | 世界の種別::間接照明の検収世界
        | 世界の種別::両視錐台外の群の検収世界
        | 世界の種別::地形世界(地形世界の種別::目視見本)
        | 世界の種別::地形世界(地形世界の種別::場所巡り)
        | 世界の種別::地形世界(地形世界の種別::エディター)
        | 世界の種別::地形世界(地形世界の種別::夜灯り) => plan::読み戻しだけの動作を導出する(),
        世界の種別::平面板
        | 世界の種別::地形世界(地形世界の種別::起点)
        | 世界の種別::地形世界(地形世界の種別::名前で選ばれない地形)
        | 世界の種別::名前で選ばれない世界 => {
            plan::現在フレームからquadシーンの動作を導出する(現在フレーム, 総フレーム数)
        }
    }
}
