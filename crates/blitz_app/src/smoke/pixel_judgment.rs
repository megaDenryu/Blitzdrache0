//! 読み戻し画像のピクセル判定。中央=quadのベースカラー(sRGBテクスチャ→リニア→sRGB出力
//! で成分値は保存される)、隅=クリアカラーをsRGB8bit・許容誤差±8で判定する(判断22)。
//! helmetは色を特定せず「中央がクリアカラーでない」ことのみ判定する。

mod expected_color;
mod srgb_convert;

use blitz_render::読み戻し画像;

use super::スモークアクション;
use crate::error::起動エラー;
use expected_color::{
    アセット反映後中央色線形値, クリアカラー線形値, 初期中央色線形値, 書き換え後中央色線形値, 許容誤差, 隅座標,
};
use srgb_convert::linearをsrgb8bit相当のf32へ変換する;

pub(crate) fn ピクセルを判定する(
    画像: &読み戻し画像,
    アクション: スモークアクション,
) -> Result<(), 起動エラー> {
    match アクション {
        スモークアクション::ヘルメット判定 => クリア色でないことを判定する(画像),
        スモークアクション::粒子判定 => 隅がクリア色であることを判定する(画像),
        _ => 期待色を判定する(画像, アクション),
    }
}

/// particlesステージ用: 粒子は画面中央付近に来るとは限らないため中央色は見ず、
/// 隅がクリアカラーのままであること(=描画範囲外まで塗りつぶされていないこと)だけを
/// 確認する(判断29)。
fn 隅がクリア色であることを判定する(画像: &読み戻し画像) -> Result<(), 起動エラー> {
    比較する(画像, 隅座標.0, 隅座標.1, クリアカラー線形値, "隅(クリアカラー)")
}

fn 期待色を判定する(画像: &読み戻し画像, アクション: スモークアクション) -> Result<(), 起動エラー> {
    let 中央期待色 = match アクション {
        スモークアクション::初期色判定 => 初期中央色線形値,
        スモークアクション::アセット反映後判定 => アセット反映後中央色線形値,
        スモークアクション::最終判定 => 書き換え後中央色線形値,
        _ => return Ok(()),
    };

    let 中央x = 画像.幅() / 2;
    let 中央y = 画像.高さ() / 2;
    比較する(画像, 中央x, 中央y, 中央期待色, "中央(quadベースカラー)")?;
    比較する(画像, 隅座標.0, 隅座標.1, クリアカラー線形値, "隅(クリアカラー)")
}

/// helmet用: 中央がクリアカラーと有意に異なる(=何か描画されている)ことのみ確認する。
fn クリア色でないことを判定する(画像: &読み戻し画像) -> Result<(), 起動エラー> {
    let 中央x = 画像.幅() / 2;
    let 中央y = 画像.高さ() / 2;
    let Some(実測) = 画像.ピクセル(中央x, 中央y) else {
        return Err(起動エラー::ピクセル判定失敗("中央: 画像範囲外だった".to_string()));
    };
    let 差分あり = クリアカラー線形値.into_iter().enumerate().any(|(添字, 線形値)| {
        let 期待値 = linearをsrgb8bit相当のf32へ変換する(線形値);
        let 実測値 = f32::from(実測[添字]);
        (実測値 - 期待値).abs() > 許容誤差
    });
    if 差分あり {
        Ok(())
    } else {
        Err(起動エラー::ピクセル判定失敗(
            "中央がクリアカラーのままだった(helmetが描画されていない)".to_string(),
        ))
    }
}

fn 比較する(
    画像: &読み戻し画像,
    x: u32,
    y: u32,
    期待線形色: [f32; 3],
    ラベル: &str,
) -> Result<(), 起動エラー> {
    let Some(実測) = 画像.ピクセル(x, y) else {
        return Err(起動エラー::ピクセル判定失敗(format!(
            "{ラベル}: 座標({x},{y})が画像範囲外だった"
        )));
    };
    for (成分添字, 線形値) in 期待線形色.into_iter().enumerate() {
        // f32→u8の安全な変換規約が標準に無いため、u8→f32(From)方向へ揃えて
        // 比較をf32領域で行い、asキャストを発生させない。
        let 期待値 = linearをsrgb8bit相当のf32へ変換する(線形値);
        let 実測値 = f32::from(実測[成分添字]);
        if (実測値 - 期待値).abs() > 許容誤差 {
            return Err(起動エラー::ピクセル判定失敗(format!(
                "{ラベル}: 成分{成分添字}が期待{期待値:.1}(±{許容誤差})に対し実測{実測値}だった"
            )));
        }
    }
    Ok(())
}
