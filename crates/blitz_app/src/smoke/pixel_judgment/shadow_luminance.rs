//! shadowステージの判定(判断37): 床面上の「影内」と「影外」の2点の輝度を
//! 相対比較する。絶対値の期待色はライティング式の二重実装になるため使わない。
//!
//! 座標は`--scene shadow_scene`の既定カメラ姿勢(判断37でシーン専用に調整、
//! 参照: blitz_app::app::scene_camera)・ウィンドウ初期寸法1280x720を前提に、
//! 光源方向とシーン形状から解析的に求めた値を固定している(このステージは
//! 自己操作でリサイズしないため決定性を保てる)。影内は遮蔽quadの影が
//! 落ちる床上の点、影外はそこから離れた床上の点。

use blitz_render::読み戻し画像;

use crate::error::起動エラー;

const 影内座標: (u32, u32) = (684, 411);
const 影外座標: (u32, u32) = (546, 288);
/// 「影内が影外の70%未満」の判定に使う倍率(判断37)。
const 影の輝度上限倍率: f32 = 0.7;

pub(super) fn 影の相対輝度を判定する(画像: &読み戻し画像) -> Result<(), 起動エラー> {
    let 影内輝度 = 輝度を求める(画像, 影内座標.0, 影内座標.1, "影内")?;
    let 影外輝度 = 輝度を求める(画像, 影外座標.0, 影外座標.1, "影外")?;

    if 影内輝度 < 影外輝度 * 影の輝度上限倍率 {
        Ok(())
    } else {
        Err(起動エラー::ピクセル判定失敗(format!(
            "影内輝度{影内輝度:.1}が影外輝度{影外輝度:.1}の{影の輝度上限倍率}倍未満になっていない(影が出ていない可能性)"
        )))
    }
}

fn 輝度を求める(画像: &読み戻し画像, x: u32, y: u32, ラベル: &str) -> Result<f32, 起動エラー> {
    let Some(実測) = 画像.ピクセル(x, y) else {
        return Err(起動エラー::ピクセル判定失敗(format!("{ラベル}: 座標({x},{y})が画像範囲外だった")));
    };
    let 合計 = f32::from(実測[0]) + f32::from(実測[1]) + f32::from(実測[2]);
    Ok(合計 / 3.0)
}
