//! shadowステージの判定(判断37): 床面上の「影内」1点と「影外」3点の輝度を比較する。
//! 絶対値の期待色はライティング式の二重実装になるため使わず、相対比較と粗い絶対下限だけを使う。
//!
//! 座標は`--scene shadow_scene`の既定カメラ姿勢(参照: blitz_app::app::scene_camera)とウィンドウ初期寸法1280x720を前提に固定している(このステージは自己操作でリサイズしないため決定的)。
//!
//! 注意: 影外を1点でなく離れた3点にするのは、M6で実際に踏んだ誤判定への対策。シャドウマップ範囲内が全面影になる壊れ方でも、範囲外(境界色=非影)の明るい領域に影外点が1つ乗ると相対比較が通ってしまう。離れた3点すべてが明るいことと、粗い絶対下限(クリア色より十分明るい=方向光が実際に床へ届いている)を同時に要求して、この壊れ方を弾く。

use blitz_render::読み戻し画像;

use crate::error::起動エラー;

const 影内座標: (u32, u32) = (684, 411);
const 影外座標一覧: [(u32, u32); 3] = [(546, 288), (800, 480), (450, 470)];
/// 「影内が影外の70%未満」の判定に使う倍率(判断37)。
const 影の輝度上限倍率: f32 = 0.7;
/// 影外の絶対下限(8bit輝度)。クリア色の輝度は約77のため、方向光が床に届いていればこれを大きく超える。
const 影外最低輝度: f32 = 110.0;

pub(super) fn 影の相対輝度を判定する(画像: &読み戻し画像) -> Result<(), 起動エラー> {
    let 影内輝度 = 輝度を求める(画像, 影内座標.0, 影内座標.1, "影内")?;
    let mut 影外最小 = f32::MAX;
    for (番号, (x, y)) in 影外座標一覧.into_iter().enumerate() {
        let 輝度 = 輝度を求める(画像, x, y, "影外")?;
        println!("[smoke] 影外{}({x},{y})の輝度: {輝度:.1}", 番号 + 1);
        if 輝度 < 影外最低輝度 {
            return Err(起動エラー::ピクセル判定失敗(format!(
                "影外{}({x},{y})の輝度{輝度:.1}が下限{影外最低輝度}未満(床が照らされていない可能性)",
                番号 + 1
            )));
        }
        影外最小 = 影外最小.min(輝度);
    }
    println!("[smoke] 影内({},{})の輝度: {影内輝度:.1}", 影内座標.0, 影内座標.1);

    if 影内輝度 < 影外最小 * 影の輝度上限倍率 {
        Ok(())
    } else {
        Err(起動エラー::ピクセル判定失敗(format!(
            "影内輝度{影内輝度:.1}が影外最小輝度{影外最小:.1}の{影の輝度上限倍率}倍未満になっていない(影が出ていない可能性)"
        )))
    }
}

fn 輝度を求める(画像: &読み戻し画像, x: u32, y: u32, ラベル: &str) -> Result<f32, 起動エラー> {
    let Some(実測) = 画像.ピクセル(x, y) else {
        return Err(起動エラー::ピクセル判定失敗(
            format!("{ラベル}: 座標({x},{y})が画像範囲外だった"),
        ));
    };
    let 合計 = f32::from(実測[0]) + f32::from(実測[1]) + f32::from(実測[2]);
    Ok(合計 / 3.0)
}
