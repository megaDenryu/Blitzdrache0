//! 二対象の格子配置が左右に分離して実際に描画されたことを読み戻し画素で判定する。

use blitz_render::読み戻し画像;

use super::compare::比較する;
use super::expected_color::{クリアカラー線形値, 初期中央色線形値};
use crate::error::起動エラー;

pub(super) fn 判定する(画像: &読み戻し画像) -> Result<(), 起動エラー> {
    let y = 画像.高さ() / 2;
    let 左x = 画像.幅() * 2 / 5;
    let 中央x = 画像.幅() / 2;
    let 右x = 画像.幅() * 3 / 5;
    比較する(画像, 左x, y, 初期中央色線形値, "左の描画対象")?;
    比較する(画像, 中央x, y, クリアカラー線形値, "描画対象間の間隙")?;
    比較する(画像, 右x, y, 初期中央色線形値, "右の描画対象")?;
    println!("[smoke] 二描画対象の左右分離ピクセル判定に成功した");
    Ok(())
}
