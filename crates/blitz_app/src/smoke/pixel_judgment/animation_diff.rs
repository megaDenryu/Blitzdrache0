//! foxステージの差分判定(判断45): 基準フレームと現在フレームの読み戻し画像を比較し、
//! アニメーションが実際に絵を動かしたこと(差分画素数が閾値以上)を判定する。

use blitz_render::読み戻し画像;

use crate::error::起動エラー;

/// 1画素を「変化した」と数えるRGB成分差の下限。読み戻しの量子化ゆらぎ(±数値)を除外する。
const 成分差下限: u8 = 12;
/// 合格に要求する変化画素数。Foxは画面の数%を占め、歩行の0.5秒で脚・尾が大きく動くため
/// 数千画素は変化する。誤検出(全静止)との分離が目的で、値は実測で調整してよい。
const 変化画素数下限: usize = 500;

pub(crate) fn 判定する(基準: &読み戻し画像, 現在: &読み戻し画像) -> Result<(), 起動エラー> {
    if 基準.幅() != 現在.幅() || 基準.高さ() != 現在.高さ() {
        return Err(起動エラー::ピクセル判定失敗(format!(
            "基準と現在の画像寸法が一致しない: {}x{} と {}x{}",
            基準.幅(),
            基準.高さ(),
            現在.幅(),
            現在.高さ()
        )));
    }

    let mut 変化画素数 = 0usize;
    for y in 0..基準.高さ() {
        for x in 0..基準.幅() {
            let (Some(a), Some(b)) = (基準.ピクセル(x, y), 現在.ピクセル(x, y)) else {
                continue;
            };
            let 差 = a.iter().zip(b.iter()).take(3).map(|(&p, &q)| p.abs_diff(q)).max().unwrap_or(0);
            if 差 >= 成分差下限 {
                変化画素数 += 1;
            }
        }
    }

    if 変化画素数 < 変化画素数下限 {
        return Err(起動エラー::ピクセル判定失敗(format!(
            "アニメーションによる画素変化が{変化画素数}画素で、下限{変化画素数下限}に満たない(絵が動いていない)"
        )));
    }
    println!("[smoke] アニメーション差分: {変化画素数}画素が変化(下限{変化画素数下限})");
    Ok(())
}
