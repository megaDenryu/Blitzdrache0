//! 起動指定の`検証計画指定`が選ぶ枝ごとのフレームスケジュール。どの枝もピクセル判定を1つも持たず、
//! 自己操作と書き換えと読み戻しの並びだけを返す。合否は検収側のxtaskがvalidation件数・GPUメモリ残数・
//! 読み戻し画像・標準出力で決める。
//!
//! 2つの枝を1つのモジュールへ置くのは、どちらもシーン名や粒子から選ぶ既定の計画を飛ばして起動指定だけで選ばれるためである。
//! シーン固有のピクセル判定を持つ計画は`plan`にあり、選ばれる経路が違う。

use super::スモークアクション;

/// リサイズ→最小化→復帰を総フレーム数の1/8刻みで踏み、残りは通常描画を続ける。
/// 復帰後に総フレーム数の5/8を通常描画に充て、再構築後のスワップチェーンで描き続けられることを確かめる。
/// ピクセル判定を1つも持たないのは、明るさの圧縮後の色に既存ステージの期待色がそのまま使えないためである。
pub(crate) fn 現在フレームからウィンドウ再構築の動作を導出する(
    現在フレーム: u32,
    総フレーム数: u32,
) -> スモークアクション {
    if 現在フレーム == 総フレーム数 / 8 {
        スモークアクション::リサイズ
    } else if 現在フレーム == 総フレーム数 * 2 / 8 {
        スモークアクション::最小化
    } else if 現在フレーム == 総フレーム数 * 3 / 8 {
        スモークアクション::復帰
    } else {
        スモークアクション::通常描画
    }
}

/// 差し替え前の絵を読み戻して保存する → 監視先のシェーダーを書き換える → 差し替え後の絵を最終フレームの読み戻しで採る。
/// 書き換えから最終フレームまでを総フレーム数の8割以上空けるのは、0.5秒ごとの確認・3本の再コンパイル・
/// 全シーンキーのパイプライン再構築・次の描画までを十分な猶予で待つためである。
pub(crate) fn 現在フレームからシェーダー差し替えの動作を導出する(
    現在フレーム: u32,
    総フレーム数: u32,
) -> スモークアクション {
    if 現在フレーム + 1 == 総フレーム数 * 2 / 24 {
        スモークアクション::差し替え前ダンプ
    } else if 現在フレーム == 総フレーム数 * 3 / 24 {
        スモークアクション::シェーダー書き換え
    } else {
        スモークアクション::通常描画
    }
}
