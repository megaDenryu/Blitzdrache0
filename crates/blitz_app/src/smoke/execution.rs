//! スモーク実行。`--frames`で起動したプロセスが、そのフレームで何を自己操作するかを決め、決めた書き換えを
//! 実行する操作サービスである。監視するシェーダーの入口ファイル・実行時アセットの置き場・差し替えの対・
//! 計画を選ぶ材料をコンストラクタ注入で保持し、フレームごとの呼び出しは番号だけを受ける。
//!
//! 依存を保持するのは、書き換えの入口が置き場と入口ファイルを毎回持参させる形だったためである。持参させる形では、
//! 「どのシーンのどの生成物をどこへ複写するのか」が呼び出し側に散り、スモークの外から誤った組み合わせを渡せる。

mod construction;
mod frame_action;
mod rewrite;
mod window_operation;

use crate::cli::{世界の種別, 差し替える生成物の対, 描画対象数, 検証計画指定, 粒子表示モード};
use crate::hot_reload::監視するシェーダーの入口ファイル;
use crate::runtime_assets::実行時アセットの置き場;

/// `--frames`で起動したプロセス1つぶんのスモーク実行。
pub(crate) struct スモーク実行 {
    シェーダーの入口ファイル: 監視するシェーダーの入口ファイル,
    アセットの置き場: 実行時アセットの置き場,
    差し替える生成物の対: 差し替える生成物の対,
    計画の材料: 計画の材料,
}

/// フレーム番号から自己操作を決めるのに要る、実行中に変わらない材料。
/// ストリーミングを有効にした実行は、起動時シーンの絵へチャンクが重なるため既存の画素判定が絵を言い当てない。
/// 合否はvalidation件数と読み戻し画像で決めるため、`ストリーミング有効`が真の実行は自己操作を1つも踏まず通常描画だけを続ける。
struct 計画の材料 {
    総フレーム数: u32,
    種別: 世界の種別,
    粒子表示: 粒子表示モード,
    開発ui有効: bool,
    布有効: bool,
    描画対象数: Option<描画対象数>,
    検証計画: 検証計画指定,
    ストリーミング有効: bool, // ストリーミングを有効にした実行か
}
