//! スモークアクションから、そのフレームで踏む自己操作を読み取る工程。受け取るのはアクション、返すのは
//! 「どのウィンドウ操作を求めるか」と「どの書き換えを求めるか」であり、求めないフレームは`None`になる。
//!
//! 求める側の枝だけを小さく数え上げてから振り分けるのは、17枝のアクションを消費側で直に`match`すると、
//! 消費側が読める長さに収まらずワイルドカードの枝へ逃げるためである。ワイルドカードへ逃げると、
//! 書き換えの枝を1つ足したときに、その枝が無言で「何もしない」へ落ちる。
//!
//! 読み取りをアクションの側へ置くのは、ここだけが網羅`match`であればよく、消費側は2枝と3枝の`match`で
//! 済むためである。アクションを1つ足すとこの2つの読み取りがコンパイルの失敗になる。

use super::スモークアクション;

/// 計画がそのフレームで求めるウィンドウの自己操作。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 求められたウィンドウ操作 {
    小さい寸法へ変える, // 既定より小さい寸法へ変える。スワップチェーンの再構築で落ちないことを確かめる
    最小化する,
    最小化から戻す,
}

/// 計画がそのフレームで求めるファイルの書き換え。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 求められた書き換え {
    監視先のシェーダーの色, // 監視先のシェーダーの入口ファイルの色の定数を書き換える
    実行時アセットの生成物, // 実行時アセットの生成物を差し替えの対で上書きする
}

impl スモークアクション {
    pub(super) fn 求めるウィンドウ操作(self) -> Option<求められたウィンドウ操作> {
        match self {
            Self::リサイズ => Some(求められたウィンドウ操作::小さい寸法へ変える),
            Self::最小化 => Some(求められたウィンドウ操作::最小化する),
            Self::復帰 => Some(求められたウィンドウ操作::最小化から戻す),
            Self::通常描画
            | Self::シェーダー書き換え
            | Self::アセット書き換え
            | Self::差し替え前ダンプ
            | Self::初期色判定
            | Self::アセット反映後判定
            | Self::最終判定
            | Self::ヘルメット判定
            | Self::粒子判定
            | Self::開発UI判定
            | Self::シャドウ判定
            | Self::複数描画対象判定
            | Self::フォックス基準保存
            | Self::フォックス差分判定 => None,
        }
    }

    pub(super) fn 求める書き換え(self) -> Option<求められた書き換え> {
        match self {
            Self::シェーダー書き換え => Some(求められた書き換え::監視先のシェーダーの色),
            Self::アセット書き換え => Some(求められた書き換え::実行時アセットの生成物),
            Self::通常描画
            | Self::リサイズ
            | Self::最小化
            | Self::復帰
            | Self::差し替え前ダンプ
            | Self::初期色判定
            | Self::アセット反映後判定
            | Self::最終判定
            | Self::ヘルメット判定
            | Self::粒子判定
            | Self::開発UI判定
            | Self::シャドウ判定
            | Self::複数描画対象判定
            | Self::フォックス基準保存
            | Self::フォックス差分判定 => None,
        }
    }
}
