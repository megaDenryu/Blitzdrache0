//! アセットホットリロード検証用の書き換え。担当するのは、起動時シーンが選んだ差し替えの対を実行時アセットの
//! ファイルの複写として実行することだけである。どの世界がどの対を使うかは`cli::起動時シーン`が決める。
//!
//! 注意: WindowsのCopyFileEx(std::fs::copyの実体)はコピー元ファイルの更新日時を
//! 先の更新日時としてそのまま引き継ぐ。2つの生成物は同じコンパイル由来のため、
//! コピーしただけでは監視側のmtime比較(現在時刻 > 記録時刻)が進まず、
//! ホットリロードが検知されない。書き込み直後に明示的に現在時刻へ更新する。
use std::path::Path;
use std::time::SystemTime;

use crate::cli::起動時シーン;
use crate::error::起動エラー;

/// 実行時アセットの拡張子。カタログが生成物へ付ける綴りと同じである。
const 実行時アセットの拡張子: &str = "blitzasset";

pub(crate) fn アセットを書き換える(アセットルート: &Path, シーン: &起動時シーン) -> Result<(), 起動エラー> {
    let 対 = シーン.差し替える生成物の対();
    let 元 = アセットルート.join(format!("{}.{実行時アセットの拡張子}", 対.複写元()));
    let 先 = アセットルート.join(format!("{}.{実行時アセットの拡張子}", 対.複写先()));
    std::fs::copy(&元, &先)
        .map_err(|誤り| 起動エラー::アセット書き換え失敗(format!("{} -> {}: {誤り}", 元.display(), 先.display())))?;

    let ファイル = std::fs::File::options()
        .write(true)
        .open(&先)
        .map_err(|誤り| 起動エラー::アセット書き換え失敗(format!("{}: {誤り}", 先.display())))?;
    ファイル
        .set_modified(SystemTime::now())
        .map_err(|誤り| 起動エラー::アセット書き換え失敗(format!("{}: {誤り}", 先.display())))
}
