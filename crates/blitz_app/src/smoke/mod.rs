//! `--frames`スモークモードの自己操作・ホットリロード検証・ピクセル判定シナリオ。
//! DoDの「三角形が表示される」「リサイズ・最小化で落ちない」「シェーダー変更の自動反映」を
//! ウィンドウの自己操作とピクセル読み戻しで機械検証する。
//! 参照: `_doc/開発スレッド/開発スレッド_2026-07-20_M0実装.md`「判断9」。

mod pixel_judgment;
mod shader_rewrite;
mod window_operation;

use winit::window::Window;

pub(crate) use pixel_judgment::ピクセルを判定する;
pub(crate) use shader_rewrite::シェーダーを書き換える;

/// フレーム番号に応じて、このフレームで行う自己操作・検証を表す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum スモークアクション {
    通常描画,
    リサイズ,
    最小化,
    復帰,
    シェーダー書き換え,
    初期色判定,
    最終判定,
}

/// スモーク計画: N/6リサイズ → N/3直前に初期色判定 → N/3最小化 → N/2復帰 →
/// 2N/3シェーダー書き換え → N-1最終判定。
pub(crate) fn 判定する(現在フレーム: u32, 総フレーム数: u32) -> スモークアクション {
    if 現在フレーム == 総フレーム数 / 6 {
        スモークアクション::リサイズ
    } else if 現在フレーム + 1 == 総フレーム数 / 3 {
        スモークアクション::初期色判定
    } else if 現在フレーム == 総フレーム数 / 3 {
        スモークアクション::最小化
    } else if 現在フレーム == 総フレーム数 / 2 {
        スモークアクション::復帰
    } else if 現在フレーム == 総フレーム数 * 2 / 3 {
        スモークアクション::シェーダー書き換え
    } else if 現在フレーム + 1 == 総フレーム数 {
        スモークアクション::最終判定
    } else {
        スモークアクション::通常描画
    }
}

pub(crate) fn window自己操作を適用する(window: &Window, アクション: スモークアクション) {
    window_operation::適用する(window, アクション);
}
