//! スモーク実行の生成局面。呼ばれるのは起動時の1回だけであり、フレームごとに呼ばれる動作の決定とは
//! 呼び出し頻度が違う。担当するのは、起動設定から保持する依存と計画の材料を取り出すことだけである。

use super::{スモーク実行, 計画の材料};
use crate::cli::{起動モード, 起動設定};

impl スモーク実行 {
    /// `--frames`で起動したときだけスモーク実行を組む。ほかのモードは自己操作も画素判定も持たないため`None`を返す。
    pub(crate) fn 起動設定から作る(起動設定: &起動設定) -> Option<Self> {
        let 起動モード::スモーク実行 { フレーム数 } = 起動設定.モード else {
            return None;
        };
        Some(Self {
            シェーダーの入口ファイル: 起動設定.シェーダーの入口ファイル.clone(),
            アセットの置き場: 起動設定.アセットの置き場.clone(),
            差し替える生成物の対: 起動設定.シーン.差し替える生成物の対(),
            計画の材料: 計画の材料 {
                総フレーム数: フレーム数,
                種別: 起動設定.シーン.種別(),
                粒子表示: 起動設定.粒子表示,
                開発uiを有効にするか: 起動設定.開発ui初期有効,
                布を有効にするか: 起動設定.布モード != crate::cli::布モード::なし,
                描画対象数: 起動設定.描画対象の並べ方.件数,
                検証計画: 起動設定.検証計画,
                ストリーミングを有効にした実行か: 起動設定.ストリーミング.有効,
            },
        })
    }
}
