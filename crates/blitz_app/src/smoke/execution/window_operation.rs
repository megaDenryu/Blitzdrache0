//! 計画が求めたウィンドウの自己操作を適用する局面。呼ばれるのは毎フレームであり、書き換えとは触れる相手が違う。
//! 担当するのは、求められた操作をwinitのウィンドウへの呼び出しへ振り分けることだけである。
//!
//! ウィンドウだけをコンストラクタ注入でなくメソッドの引数で受ける。winitのウィンドウは`resumed`より後にしか
//! 存在せず、スモーク実行は起動設定から`resumed`より前に組むためである。枠組みが決めた生存期間の制約であり、
//! この1つだけが例外になる。ほかの依存(入口ファイル・置き場・差し替えの対)は保持している。

use winit::dpi::PhysicalSize;
use winit::window::Window;

use super::スモーク実行;
use crate::smoke::action_demand::求められたウィンドウ操作;
use crate::smoke::スモークアクション;

/// 小さい寸法へ変えるときの物理画素の幅と高さ。既定より小さくすることがスワップチェーンの再構築を起こす。
const 小さい寸法の幅: u32 = 480;
const 小さい寸法の高さ: u32 = 360;

impl スモーク実行 {
    pub(crate) fn ウィンドウへ自己操作を適用する(&self, window: &Window, アクション: スモークアクション) {
        let Some(操作) = アクション.求めるウィンドウ操作() else {
            return;
        };
        match 操作 {
            求められたウィンドウ操作::小さい寸法へ変える => {
                // 要求が容れられなかったときは次のフレームの寸法が変わらないだけであり、検収は読み戻し画像で判定する。
                let _ = window.request_inner_size(PhysicalSize::new(小さい寸法の幅, 小さい寸法の高さ));
            }
            求められたウィンドウ操作::最小化する => window.set_minimized(true),
            求められたウィンドウ操作::最小化から戻す => window.set_minimized(false),
        }
    }
}
