//! 計画が求めた書き換えを実行する局面。呼ばれるのは計画が書き換えの動作を返したフレームだけであり、
//! 毎フレーム呼ばれる動作の決定とは呼び出し頻度が違う。
//!
//! シェーダーの置換の文面をここが持つのは、書き換える側と検収側のxtaskが同じ綴りを見る必要が無く、
//! 「初期の色の行が在ること」自体をこの検収の前提として確かめるためである。表記は`cube.slang`の1行とそのまま一致させる。

use super::スモーク実行;
use crate::error::起動エラー;
use crate::smoke::action_demand::求められた書き換え;
use crate::smoke::スモークアクション;

const 初期色の行: &str = "static const float3 TINT = float3(1.0, 1.0, 1.0);";
const 書き換え後の行: &str = "static const float3 TINT = float3(0.1, 0.9, 0.2);";

impl スモーク実行 {
    pub(crate) fn 書き換えを適用する(&self, アクション: スモークアクション) -> Result<(), 起動エラー> {
        let Some(書き換え) = アクション.求める書き換え() else {
            return Ok(());
        };
        match 書き換え {
            求められた書き換え::監視先のシェーダーの色 => self.シェーダーの色を書き換える(),
            求められた書き換え::実行時アセットの生成物 => {
                self.アセットの置き場.生成物を差し替える(&self.差し替える生成物の対)
            }
        }
    }

    fn シェーダーの色を書き換える(&self) -> Result<(), 起動エラー> {
        let 内容 = self
            .シェーダーの入口ファイル
            .本文を読む()
            .map_err(|誤り| 起動エラー::シェーダー書き換え失敗(format!("読み込みに失敗した: {誤り}")))?;
        if !内容.contains(初期色の行) {
            return Err(起動エラー::シェーダー書き換え失敗(
                "置換対象の行が見つからなかった".to_string(),
            ));
        }
        self.シェーダーの入口ファイル
            .本文を書き出す(&内容.replace(初期色の行, 書き換え後の行))
            .map_err(|誤り| 起動エラー::シェーダー書き換え失敗(format!("書き込みに失敗した: {誤り}")))
    }
}
