//! フレーム番号からそのフレームの自己操作を決める局面。呼ばれるのは毎フレームであり、起動時の1回だけ呼ばれる
//! 生成とは呼び出し頻度が違う。担当するのは、計画の材料から計画を1つ選び、その計画へフレーム番号を渡すことだけである。
//!
//! 選ぶ順序に意味がある。起動指定が直に選ぶ計画とストリーミングの実行はどちらも画素判定を持たないため、
//! シーン・粒子・布による計画の選択より先に決める。

use super::{スモーク実行, 計画の材料};
use crate::cli::{検証計画指定, 粒子表示モード};
use crate::smoke::{plan, verification_plan, world_plan, スモークアクション};

impl スモーク実行 {
    pub(crate) fn このフレームの動作を決める(&self, 現在フレーム: u32) -> スモークアクション {
        self.計画の材料.動作を導出する(現在フレーム)
    }
}

impl 計画の材料 {
    fn 動作を導出する(&self, 現在フレーム: u32) -> スモークアクション {
        match self.検証計画 {
            検証計画指定::ウィンドウ再構築 => {
                return verification_plan::現在フレームからウィンドウ再構築の動作を導出する(現在フレーム, self.総フレーム数);
            }
            検証計画指定::シェーダー差し替え => {
                return verification_plan::現在フレームからシェーダー差し替えの動作を導出する(
                    現在フレーム,
                    self.総フレーム数,
                );
            }
            検証計画指定::指定なし => {}
        }
        if self.ストリーミング有効 {
            return スモークアクション::通常描画;
        }
        self.世界と道具から導出する(現在フレーム)
    }

    /// `布有効`なら差分計画(布は厳密な画素判定と両立しないため。判断55・56)、`開発ui有効`ならdevui計画、
    /// 粒子トイならparticles計画、表面流ならGPU計測だけを行う。どれにも当たらなければ世界の種別ごとの計画を選ぶ
    /// (判断29・34・37・45)。
    fn 世界と道具から導出する(&self, 現在フレーム: u32) -> スモークアクション {
        if self.描画対象数.map(crate::cli::描画対象数::usize値) == Some(2) {
            plan::現在フレームから複数描画対象の動作を導出する(現在フレーム, self.総フレーム数)
        } else if self.布有効 {
            plan::現在フレームからフォックスの動作を導出する(現在フレーム)
        } else if self.開発ui有効 {
            plan::現在フレームから開発uiの動作を導出する(現在フレーム, self.総フレーム数)
        } else if matches!(
            self.粒子表示,
            粒子表示モード::表面流 | 粒子表示モード::Sph512 | 粒子表示モード::Sph1024 | 粒子表示モード::Sph2048
        ) {
            スモークアクション::通常描画
        } else if self.粒子表示 == 粒子表示モード::粒子トイ {
            plan::現在フレームから粒子の動作を導出する(現在フレーム, self.総フレーム数)
        } else {
            world_plan::世界ごとの動作を導出する(現在フレーム, self.総フレーム数, self.種別)
        }
    }
}
