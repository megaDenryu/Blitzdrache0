//! ホットリロードの1回の確認が返す結果の数え上げ。担当するのは枝の定義だけであり、いつ確認するかと
//! どう反映するかは持たない。
//!
//! 監視の実装から分けるのは、この数え上げがホットリロードの唯一の公開の口であり、読み手が
//! mtimeの走査もslangcの起動も読まずに「何が起こりうるか」だけを見られるようにするためである。

use blitz_engine::surface_layer_textures::地表層テクスチャ集の読み口;
use blitz_engine::{カタログ, シーンデータ, チャンク目録, 実行時シーンの内容};
use blitz_render::indirect_lighting::契約別のシーン描画シェーダー;

use super::{シェーダー再コンパイルエラー, 実行時アセット一式の再読込エラー};

/// 世界に1つだけ置く地表層テクスチャ集も一式に載せるのは、層のタイルがカタログと同じ世代でなければ
/// ならないためである。載せずにおくと、タイルを持たない世界からタイルを持つ世界へ焼き直したときに、
/// 起動時に読んだ「タイルを持たない世界」が残り、ストリーミングが地表材質を組めずに失敗し続ける。
pub(crate) struct 公開済みの実行時アセット一式 {
    pub(crate) カタログ: カタログ,
    pub(crate) チャンク目録: チャンク目録,
    pub(crate) 地表層テクスチャ集: 地表層テクスチャ集の読み口,
    pub(crate) 起動時シーン: 起動時シーンの更新,
    pub(crate) 公開完了印: crate::runtime_assets::生成台帳の公開内容,
}

pub(crate) enum 起動時シーンの更新 {
    同じ内容 {
        内容: 実行時シーンの内容,
    },
    変更あり {
        内容: 実行時シーンの内容,
        シーン: シーンデータ,
    },
}

/// `ホットリローダー::確認する` の結果。
pub(crate) enum ホットリロード結果 {
    変化なし,
    シェーダー再コンパイル成功 {
        シェーダー: 契約別のシーン描画シェーダー,
    },
    シェーダー再コンパイル失敗 {
        誤り: シェーダー再コンパイルエラー,
    },
    // シーンデータがスキン・アニメーション追加(判断42)で大型化したため一式をBoxで持つ(clippy::large_enum_variant)。
    アセット再読込成功 {
        一式: Box<公開済みの実行時アセット一式>,
    },
    アセット再読込失敗 {
        誤り: 実行時アセット一式の再読込エラー,
    },
}
