//! ホットリロードの1回の確認が返す結果の数え上げ。担当するのは枝の定義だけであり、いつ確認するかと
//! どう反映するかは持たない。
//!
//! 監視の実装から分けるのは、この数え上げがホットリロードの唯一の公開の口であり、読み手が
//! mtimeの走査もslangcの起動も読まずに「何が起こりうるか」だけを見られるようにするためである。

use blitz_engine::シーンデータ;
use blitz_render::indirect_lighting::契約別の描画シェーダー;

use super::シェーダー再コンパイルエラー;

/// `ホットリローダー::確認する` の結果。
pub(crate) enum ホットリロード結果 {
    変化なし,
    シェーダー再コンパイル成功 {
        シェーダー: 契約別の描画シェーダー,
    },
    シェーダー再コンパイル失敗 {
        誤り: シェーダー再コンパイルエラー,
    },
    // シーンデータがスキン・アニメーション追加(判断42)で大型化したためBoxで持つ(clippy::large_enum_variant)。
    アセット再読込成功 {
        シーン: Box<シーンデータ>,
    },
    アセット再読込失敗 {
        誤り: blitz_engine::実行時シーン読込エラー,
    },
}
