//! 生成台帳を公開完了の印として監視し、実行時アセット一式を同じ世代から読み直す。

mod asset_watch_tests;

use blitz_engine::surface_layer_textures::地表層テクスチャ集の読み口;
use blitz_engine::{アセットID, カタログ, 実行時シーンのファイル, 実行時シーンの内容};

use super::asset_reload_error::実行時アセット一式の再読込エラー;
use super::reload_result::{公開済みの実行時アセット一式, 起動時シーンの更新};
use crate::runtime_assets::{実行時アセットの置き場, 生成台帳の公開内容};

pub(super) struct アセット監視状態 {
    置き場: 実行時アセットの置き場,
    カタログ: カタログ,
    id: アセットID,
    確認済みの公開完了印: Option<生成台帳の公開内容>,
    確認済みの起動時シーン: Option<実行時シーンの内容>,
}

pub(super) fn アセット監視状態を構築する(
    置き場: 実行時アセットの置き場,
    カタログ: カタログ,
    id: アセットID,
) -> アセット監視状態 {
    let 確認済みの公開完了印 = 置き場.生成台帳の公開内容を読む().ok();
    let 確認済みの起動時シーン = 実行時シーンのファイル::カタログの安定idから作る(&カタログ, &id).and_then(|ファイル| ファイル.内容を読み込む().ok());
    アセット監視状態 {
        置き場,
        カタログ,
        id,
        確認済みの公開完了印,
        確認済みの起動時シーン,
    }
}

impl アセット監視状態 {
    pub(super) fn カタログ(&self) -> &カタログ {
        &self.カタログ
    }

    pub(super) fn 実行時アセット一式を採用する(
        &mut self,
        カタログ: カタログ,
        起動時シーン: 実行時シーンの内容,
        公開完了印: 生成台帳の公開内容,
    ) {
        self.カタログ = カタログ;
        self.確認済みの起動時シーン = Some(起動時シーン);
        self.確認済みの公開完了印 = Some(公開完了印);
    }

    pub(super) fn 公開完了を確認して一式を再読込する(
        &mut self,
    ) -> Option<Result<公開済みの実行時アセット一式, 実行時アセット一式の再読込エラー>> {
        let 公開完了印 = self.置き場.生成台帳の公開内容を読む().ok()?;
        if self.確認済みの公開完了印.as_ref() == Some(&公開完了印) {
            return None;
        }
        Some(self.公開済みの一式を読み込む(公開完了印))
    }

    fn 公開済みの一式を読み込む(
        &self,
        公開完了印: 生成台帳の公開内容,
    ) -> Result<公開済みの実行時アセット一式, 実行時アセット一式の再読込エラー> {
        let カタログ = self.置き場.カタログのファイル().読み込む()?;
        let チャンク目録 = self.置き場.チャンク目録のファイル().読み込む()?;
        let 地表層テクスチャ集 = 地表層テクスチャ集の読み口::カタログから読み込む(&カタログ)?;
        let 内容 = 実行時シーンのファイル::カタログの安定idから作る(&カタログ, &self.id)
            .ok_or_else(|| blitz_engine::実行時シーン読込エラー::カタログ未登録(self.id.clone()))?
            .内容を読み込む()?;
        let 起動時シーン = if self
            .確認済みの起動時シーン
            .as_ref()
            .is_some_and(|確認済み| 確認済み.格納バイト列が同じか(&内容))
        {
            起動時シーンの更新::同じ内容 { 内容 }
        } else {
            let シーン = 内容.シーンデータへ読む()?;
            起動時シーンの更新::変更あり { 内容, シーン }
        };
        Ok(公開済みの実行時アセット一式 {
            カタログ,
            チャンク目録,
            地表層テクスチャ集,
            起動時シーン,
            公開完了印,
        })
    }
}
