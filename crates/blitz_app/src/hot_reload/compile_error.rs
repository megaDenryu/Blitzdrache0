//! シェーダーの再コンパイルが途中で止まる原因。ホットリロードの失敗は描画を止めず、旧いパイプラインが
//! そのまま描き続けるため、起動エラーへは合流させずホットリロードの中で閉じる。

use std::path::PathBuf;

use thiserror::Error;

#[derive(Debug, Error)]
pub(crate) enum シェーダー再コンパイルエラー {
    #[error("slangcが見つからない。VULKAN_SDK環境変数かPATHを確認すること")]
    スランガーが見つからない,

    #[error("監視先{}に親ディレクトリが無く遠方環境の画素段を解決できない", .監視先.display())]
    監視先に親ディレクトリが無い { 監視先: PathBuf },

    #[error("一時ディレクトリの作成に失敗した: {誤り}")]
    一時ディレクトリを作れない { 誤り: std::io::Error },

    #[error("slangcの起動に失敗した: {誤り}")]
    スランガーを起動できない { 誤り: std::io::Error },

    #[error("slangcが{段の説明}のコンパイルに失敗した:\n{標準エラー出力}")]
    スランガーが失敗した { 段の説明: String, 標準エラー出力: String },

    #[error("コンパイル結果の読み込みに失敗した: {誤り}")]
    コンパイル結果を読めない { 誤り: std::io::Error },

    #[error("契約別のシーン描画シェーダーを組み立てられない: {0}")]
    描画シェーダー束が組めない(#[from] blitz_render::シェーダー一式エラー),
}
