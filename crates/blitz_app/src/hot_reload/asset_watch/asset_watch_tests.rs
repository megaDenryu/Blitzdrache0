//! 公開済みの一式の再読込が、新しいカタログと同じ世代の地表層テクスチャ集を運ぶことの試験。
//!
//! タイルを持たない世界からタイルを持つ世界へ焼き直した遷移をここで固定するのは、一式へ載せ忘れると
//! 起動時に読んだ「タイルを持たない世界」が残り、地表材質を持つチャンクのストリーミングが失敗し続けるためである。

#![cfg(test)]
#![allow(clippy::unwrap_used)]

mod fixture;

use blitz_engine::surface_layer_textures::地表層テクスチャ集の読み口;
use blitz_engine::アセットID;

use self::fixture::{一式を書き出す, 試験の世界の種別, 試験の置き場を用意する, 起動時シーンの安定IDの綴り};
use super::アセット監視状態を構築する;
use crate::runtime_assets::実行時アセットの置き場;

#[test]
fn タイルを持たない世界から持つ世界へ焼き直すと再読込がテクスチャ集を運ぶ() {
    let ディレクトリ = 試験の置き場を用意する("tiles_added");
    一式を書き出す(&ディレクトリ, "世代1", 試験の世界の種別::タイルを持たない世界);
    let mut 監視 = 監視状態を作る(&ディレクトリ);
    assert!(監視.公開完了を確認して一式を再読込する().is_none());

    一式を書き出す(&ディレクトリ, "世代2", 試験の世界の種別::タイルを持つ世界);
    let 一式 = 監視.公開完了を確認して一式を再読込する().unwrap().unwrap();
    let 地表層テクスチャ集の読み口::テクスチャ集を持つ世界(集) = 一式.地表層テクスチャ集 else {
        panic!("焼き直したカタログの地表層テクスチャ集が一式へ載っていない");
    };
    assert_eq!(集.材質ごとのタイル().len(), 4);
}

#[test]
fn タイルを外して焼き直すと再読込が持たない世界を運ぶ() {
    let ディレクトリ = 試験の置き場を用意する("tiles_removed");
    一式を書き出す(&ディレクトリ, "世代1", 試験の世界の種別::タイルを持つ世界);
    let mut 監視 = 監視状態を作る(&ディレクトリ);

    一式を書き出す(&ディレクトリ, "世代2", 試験の世界の種別::タイルを持たない世界);
    let 一式 = 監視.公開完了を確認して一式を再読込する().unwrap().unwrap();
    assert!(matches!(一式.地表層テクスチャ集, 地表層テクスチャ集の読み口::テクスチャ集を持たない世界));
}

fn 監視状態を作る(ディレクトリ: &std::path::Path) -> super::アセット監視状態 {
    let 置き場 = 実行時アセットの置き場::綴りから生成する(ディレクトリ.to_str().unwrap());
    let カタログ = 置き場.カタログのファイル().読み込む().unwrap();
    let id = アセットID::生成する(起動時シーンの安定IDの綴り).unwrap();
    アセット監視状態を構築する(置き場, カタログ, id)
}
