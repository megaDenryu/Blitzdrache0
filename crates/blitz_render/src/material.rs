//! シェーディングモデルごとのマテリアル素材。地表の層の重ね合わせの素材は`surface_layer`、層の数の写しは`layer_count`が持つ。

mod layer_count;
mod surface_layer;

pub use layer_count::地表層の数;
pub use surface_layer::地表の層の重ね合わせ素材;

use crate::pbr_material::金属粗さPBR素材;
use crate::texture_material::テクスチャ素材;
use crate::vulkan::material_table::材質テクスチャ役割;
use crate::vulkan::material_variant::シェーディングモデル種別;

/// マテリアル種別を型で判別し、新しい方式の追加時に全使用箇所を網羅検査する。
#[derive(Debug, Clone)]
pub enum マテリアル素材 {
    金属粗さPBR(金属粗さPBR素材),
    地表の層の重ね合わせ(地表の層の重ね合わせ素材),
}

impl マテリアル素材 {
    /// 材質の3軸のうち、照明式が相互排他的に変わる軸。材質変種キーの導出はこの値を材料にする。
    pub(crate) const fn シェーディングモデル種別(&self) -> シェーディングモデル種別 {
        match self {
            Self::金属粗さPBR(_) => シェーディングモデル種別::標準金属粗さPBR,
            Self::地表の層の重ね合わせ(_) => シェーディングモデル種別::地表の層の重ね合わせ,
        }
    }

    /// 役割で1枚を引く。役割から名前を選ぶ対応をここ1箇所に置くことで、材質レコードの並びと標本の並びがずれない。
    /// 自分の枝に無い役割が`None`になるのは、その材質がその役割のテクスチャを持たないという意味そのものである。
    pub(crate) fn 役割のテクスチャ(&self, 役割: 材質テクスチャ役割) -> Option<&テクスチャ素材> {
        match self {
            Self::金属粗さPBR(素材) => 素材.役割のテクスチャ(役割),
            Self::地表の層の重ね合わせ(素材) => 素材.役割のテクスチャ(役割),
        }
    }

    /// 地表の層の重ね合わせがベースカラー係数を等倍で返すのは、その枝のアルベドを層の混ぜ合わせだけが決めるためである。
    /// 材質レコードの欄はシェーディングモデルに依らず1本であり、その枝の画素段はこの欄を読まない。
    pub(crate) fn ベースカラー係数(&self) -> [f32; 4] {
        match self {
            Self::金属粗さPBR(素材) => 素材.ベースカラー係数(),
            Self::地表の層の重ね合わせ(_) => [1.0; 4],
        }
    }

    pub(crate) fn 金属度係数(&self) -> f32 {
        match self {
            Self::金属粗さPBR(素材) => 素材.金属度係数(),
            Self::地表の層の重ね合わせ(素材) => 素材.金属度係数(),
        }
    }

    pub(crate) fn 粗さ係数(&self) -> f32 {
        match self {
            Self::金属粗さPBR(素材) => 素材.粗さ係数(),
            Self::地表の層の重ね合わせ(素材) => 素材.粗さ係数(),
        }
    }

    /// 標準金属粗さPBRが等倍を返すのは、ベースカラー係数と同じ理由である。その枝の画素段はこの欄を読まない。
    pub(crate) fn 地表の層ごとのタイル倍率(&self) -> [f32; 地表層の数] {
        match self {
            Self::金属粗さPBR(_) => [1.0; 地表層の数],
            Self::地表の層の重ね合わせ(素材) => 素材.層ごとのタイル倍率(),
        }
    }
}
