//! 1フレームが通る段階の語彙と、段階どうしの前後関係を決める順位。
//!
//! 順位を段階自身が持つのは、段階列の妥当性(重複が無く順位が単調に増える)を検査する側が、段階の並びの正本をもう1つ持たないためである。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum フレーム段階 {
    スキニング,
    布シミュレーション,
    影,
    シーン,
    空,
    粒子,
    光のにじみと明るさの圧縮,
    UI,
    読み戻し,
}

impl フレーム段階 {
    pub fn 名称(self) -> &'static str {
        match self {
            Self::スキニング => "スキニング",
            Self::布シミュレーション => "布シミュレーション",
            Self::影 => "影",
            Self::シーン => "シーン",
            Self::空 => "空",
            Self::粒子 => "粒子",
            Self::光のにじみと明るさの圧縮 => "光のにじみと明るさの圧縮",
            Self::UI => "UI",
            Self::読み戻し => "読み戻し",
        }
    }

    pub(super) fn 順位(self) -> u8 {
        match self {
            Self::スキニング => 0,
            Self::布シミュレーション => 1,
            Self::影 => 2,
            Self::シーン => 3,
            Self::空 => 4,
            Self::粒子 => 5,
            Self::光のにじみと明るさの圧縮 => 6,
            Self::UI => 7,
            Self::読み戻し => 8,
        }
    }
}
