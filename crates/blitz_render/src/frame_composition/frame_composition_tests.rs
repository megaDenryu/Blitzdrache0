use crate::{フレームの処理位置, フレーム構成, フレーム構成エラー};

#[test]
fn 依存順のフレームの処理位置の列を保持する() {
    let 構成 = フレーム構成::生成する(&[フレームの処理位置::スキニング, フレームの処理位置::影, フレームの処理位置::シーン, フレームの処理位置::読み戻し]);

    assert!(構成.is_ok());
}

#[test]
fn 重複と逆順を拒否する() {
    let 逆順 = フレーム構成::生成する(&[フレームの処理位置::シーン, フレームの処理位置::影]);
    let 重複 = フレーム構成::生成する(&[フレームの処理位置::影, フレームの処理位置::影, フレームの処理位置::シーン]);

    assert!(matches!(逆順, Err(フレーム構成エラー::重複または順序不正)));
    assert!(matches!(重複, Err(フレーム構成エラー::重複または順序不正)));
}

#[test]
fn 必須の処理位置の欠落を拒否する() {
    let 結果 = フレーム構成::生成する(&[フレームの処理位置::影]);

    assert!(matches!(結果, Err(フレーム構成エラー::シーンなし)));
}
