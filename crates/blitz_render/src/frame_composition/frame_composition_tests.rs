use crate::{フレーム構成, フレーム構成エラー, フレーム段階};

#[test]
fn 依存順の段階列を保持する() {
    let 構成 = フレーム構成::生成する(&[フレーム段階::スキニング, フレーム段階::影, フレーム段階::シーン, フレーム段階::読み戻し]);

    assert!(構成.is_ok());
}

#[test]
fn 重複と逆順を拒否する() {
    let 逆順 = フレーム構成::生成する(&[フレーム段階::シーン, フレーム段階::影]);
    let 重複 = フレーム構成::生成する(&[フレーム段階::影, フレーム段階::影, フレーム段階::シーン]);

    assert!(matches!(逆順, Err(フレーム構成エラー::重複または順序不正)));
    assert!(matches!(重複, Err(フレーム構成エラー::重複または順序不正)));
}

#[test]
fn 必須段階の欠落を拒否する() {
    let 結果 = フレーム構成::生成する(&[フレーム段階::影]);

    assert!(matches!(結果, Err(フレーム構成エラー::シーンなし)));
}
