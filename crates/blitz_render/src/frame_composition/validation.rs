//! フレーム段階列の依存順序と必須段階を検査する。

use super::{フレーム構成エラー, フレーム段階, 段階数上限};

pub(super) fn 検証する(段階一覧: &[フレーム段階]) -> Result<(), フレーム構成エラー> {
    if 段階一覧.is_empty() {
        return Err(フレーム構成エラー::空);
    }
    if 段階一覧.len() > 段階数上限 {
        return Err(フレーム構成エラー::段階数超過);
    }
    for 組 in 段階一覧.windows(2) {
        if 組[0].順位() >= 組[1].順位() {
            return Err(フレーム構成エラー::重複または順序不正);
        }
    }
    if !段階一覧.contains(&フレーム段階::影) {
        return Err(フレーム構成エラー::影なし);
    }
    if !段階一覧.contains(&フレーム段階::シーン) {
        return Err(フレーム構成エラー::シーンなし);
    }
    Ok(())
}
