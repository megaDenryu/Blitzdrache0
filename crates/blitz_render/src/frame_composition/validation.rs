//! フレームの処理位置の列の依存順序と必須の処理位置を検査する。

use super::{フレームの処理位置, フレームの処理位置の数の上限, フレーム構成エラー};

pub(super) fn フレームの処理位置の列を検証する(処理位置の一覧: &[フレームの処理位置]) -> Result<(), フレーム構成エラー> {
    if 処理位置の一覧.is_empty() {
        return Err(フレーム構成エラー::空);
    }
    if 処理位置の一覧.len() > フレームの処理位置の数の上限 {
        return Err(フレーム構成エラー::処理位置の数の超過);
    }
    for 組 in 処理位置の一覧.windows(2) {
        if 組[0].順位() >= 組[1].順位() {
            return Err(フレーム構成エラー::重複または順序不正);
        }
    }
    if !処理位置の一覧.contains(&フレームの処理位置::影) {
        return Err(フレーム構成エラー::影なし);
    }
    if !処理位置の一覧.contains(&フレームの処理位置::シーン) {
        return Err(フレーム構成エラー::シーンなし);
    }
    Ok(())
}
