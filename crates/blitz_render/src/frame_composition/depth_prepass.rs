//! そのフレームへ深度プリパスを積むかどうかと、色パスが深度をどう比べるかの宣言。世界でなく起動時の計測条件が選ぶ軸である。
//! 段階列と同じくフレームの組み立て方を決める値であるため、フレーム構成の下に置く。
//!
//! 3つを1つの判別共用体で持つのは、「プリパスを積むか」と「色パスの深度の扱い」が独立に選べる2つの真偽値ではないためである。
//! プリパスを積まずに色パスを等値で比べる組み合わせは、深度が1つも書かれていない画面へ等値の判定を掛けることになり、
//! 何も描かれない絵を無言で作る。真偽値を2つ並べて持つと、この不正な組み合わせが呼び出し側の規律にしか守られない。
//!
//! 既定が`使わない`であるのは、本番の絵をこの段では1画素も変えないためである。費用の計測と正式な裁定を経るまで、
//! 積む枝は計測の起動指定からだけ選ばれる(参照: `_doc/設計/放射輝度問い合わせ階層.md`「IIaの実装設計」)。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 深度プリパス方式 {
    /// 深度プリパスを積まず、色パスがより近いものだけを描いて深度も書く。
    使わない,
    /// 深度プリパスを積み、色パスは同値以下を描いて深度も書く。深度プリパスが書いた値と等しい画素を色パスが落とさないために、比べ方を同値以下へ広げる。
    使い色は同値以下で比べる,
    /// 深度プリパスを積み、色パスは等値だけを描いて深度を書かない。プリパスと色パスが同じ位置を出すことが成立条件である。
    使い色は等値で比べる,
}

impl 深度プリパス方式 {
    pub const fn 深度プリパスを積むか(self) -> bool {
        match self {
            Self::使わない => false,
            Self::使い色は同値以下で比べる | Self::使い色は等値で比べる => true,
        }
    }

    /// 報告と計測の生値で条件を見分ける名前。
    pub const fn 名前(self) -> &'static str {
        match self {
            Self::使わない => "使わない",
            Self::使い色は同値以下で比べる => "同値以下",
            Self::使い色は等値で比べる => "等値",
        }
    }
}
