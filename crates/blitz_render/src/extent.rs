//! 物理ピクセル単位のウィンドウ寸法を表す値オブジェクト。

/// スワップチェーンの生成・再構築に使う物理ピクセル寸法。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ウィンドウ寸法 {
    幅: u32,
    高さ: u32,
}

impl ウィンドウ寸法 {
    /// 物理ピクセルの幅・高さから寸法を生成する。
    pub fn 生成する(幅: u32, 高さ: u32) -> Self {
        Self { 幅, 高さ }
    }

    /// 物理ピクセル幅。
    pub fn 幅(&self) -> u32 {
        self.幅
    }

    /// 物理ピクセル高さ。
    pub fn 高さ(&self) -> u32 {
        self.高さ
    }

    /// 幅・高さのいずれかが0か。Windowsは最小化時にこの寸法でResizedイベントを送るため、
    /// 呼び出し側はこの状態でスワップチェーンを触ってはならない。
    pub fn ゼロ寸法か(&self) -> bool {
        self.幅 == 0 || self.高さ == 0
    }
}
