//! 点光源の影の立方体配列が持てる件数と層数と一辺。触れる状態を持たず、担うのは3つの値と、
//! 件数と面の数から層の総数を導くことである。
//!
//! 参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断l: 512×512×24層の立方体互換の2D配列画像1枚を持ち、平面へ詰める集約画像を採らない」

use crate::cube_image::立方体の全面;

/// 1フレームで影を持てる灯の上限件数。宣言がこれを超えたら、局所光源列を完成させる口が型付きの失敗にする。
///
/// 4件にした根拠は2つある。屋内1部屋を照らす灯と、夜の街灯のうち手前の数件が影を落とせれば検収の目的を満たすこと。
/// 1件あたり6層で1層が512×512のD32_SFLOATであるから、4件の常駐量が24MiBに収まり、多段影の256MiBより1桁小さいことである。
pub const 影を持てる灯の上限件数: usize = 4;

/// 立方体配列の層の総数。灯1件につき立方体1つ、立方体1つにつき6面である。
pub const 点光源の影の層の総数: usize = 影を持てる灯の上限件数 * 立方体の全面.len();

/// 立方体の1つの面の一辺のテクセル数。
///
/// 512にした根拠は、影が落ちる範囲が灯の影響半径(数メートルから数十メートル)に限られ、
/// 方向光の多段影のように世界の広さを1枚で覆う必要が無いことである。
/// 常駐量はこの値の二乗に比例するため、上げるときは層の総数と合わせて予算を読み直す。
pub const 点光源の影の面の一辺: u32 = 512;
