//! 面ごとの投影と立方体の写像の突き合わせ。面の中心が主軸を指すことと、投影が写した正規化装置座標が
//! 立方体の写像の面内位置と一致することを見る。
//!
//! 一致することが、描いたテクセルと標本するテクセルが同じであることの根拠である。ここが外れると、
//! 影が面の中で上下左右にずれるか、面ごとに入れ替わる。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::face_basis::面の直交基底を求める;
use super::projection_contract::投影の契約;
use super::test_fixture::{遠面を指定した契約, 面へ写す};
use crate::clustered_lighting::影響半径;
use crate::cube_image::{向きから面と面内位置を求める, 立方体の全面, 立方体の面};

/// 影響半径が近面以下なら型付きの失敗になる。既定値で黙って埋めない。
#[test]
fn 影響半径が近面以下なら契約を作れない() {
    let 半径 = 影響半径::生成する(メートル::生成する(0.01)).unwrap();
    assert!(投影の契約::影響半径から生成する(半径).is_err());
}

/// 面の中心へ向かう向きは、その面の正規化装置座標の中心へ写る。
#[test]
fn 六主軸の向きが対応する面の中心へ写る() {
    let 契約 = 遠面を指定した契約(20.0);
    let 組 = [
        (立方体の面::第一軸の正, [3.0, 0.0, 0.0]),
        (立方体の面::第一軸の負, [-3.0, 0.0, 0.0]),
        (立方体の面::第二軸の正, [0.0, 3.0, 0.0]),
        (立方体の面::第二軸の負, [0.0, -3.0, 0.0]),
        (立方体の面::第三軸の正, [0.0, 0.0, 3.0]),
        (立方体の面::第三軸の負, [0.0, 0.0, -3.0]),
    ];
    for (面, 相対位置) in 組 {
        let 写した = 面へ写す(契約, 面, 相対位置);
        assert!(写した[0].abs() < 1.0e-6, "{面:?}の中心の横が{}になった", 写した[0]);
        assert!(写した[1].abs() < 1.0e-6, "{面:?}の中心の縦が{}になった", 写した[1]);
    }
}

/// 面ごとの投影が写した正規化装置座標と、立方体の写像が返す面内位置が一致する。
#[test]
fn 面ごとの投影と立方体の写像が同じ面内位置を指す() {
    let 契約 = 遠面を指定した契約(50.0);
    let 位置一覧 = [-0.7_f32, -0.25, 0.0, 0.3, 0.8];
    for 面 in 立方体の全面 {
        for 横 in 位置一覧 {
            for 縦 in 位置一覧 {
                突き合わせる(契約, 面, 横, 縦);
            }
        }
    }
}

fn 突き合わせる(契約: 投影の契約, 面: 立方体の面, 横: f32, 縦: f32) {
    let 基底 = 面の直交基底を求める(面);
    let 面までの距離 = 4.0_f32;
    let (前, 右, 上) = (基底.前方向き(), 基底.右向き(), 基底.上向き());
    let 相対位置 = [
        (前.x() + 右.x() * 横 + 上.x() * 縦) * 面までの距離,
        (前.y() + 右.y() * 横 + 上.y() * 縦) * 面までの距離,
        (前.z() + 右.z() * 横 + 上.z() * 縦) * 面までの距離,
    ];
    let 写した = 面へ写す(契約, 面, 相対位置);
    let 向き = [f64::from(相対位置[0]), f64::from(相対位置[1]), f64::from(相対位置[2])];
    let (写像の面, 写像の横, 写像の縦) = 向きから面と面内位置を求める(向き).unwrap();
    assert_eq!(写像の面, 面, "面{面:?}へ置いた点が{写像の面:?}と判定された");
    let 投影の横 = f64::from(写した[0]) * 0.5 + 0.5;
    let 投影の縦 = f64::from(写した[1]) * 0.5 + 0.5;
    assert!(
        (投影の横 - 写像の横).abs() < 1.0e-5,
        "{面:?}の横が投影{投影の横}と写像{写像の横}で食い違った"
    );
    assert!(
        (投影の縦 - 写像の縦).abs() < 1.0e-5,
        "{面:?}の縦が投影{投影の縦}と写像{写像の縦}で食い違った"
    );
}
