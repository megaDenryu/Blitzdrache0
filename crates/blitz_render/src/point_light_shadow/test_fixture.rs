//! 投影の契約の検査が共有する器。担うのは、灯を原点に置いた契約を作ることと、表面の相対位置を
//! その面の正規化装置座標へ写すことである。検査そのものは持たない。

use blitz_math::{メートル, ワールド, 位置};

use super::projection_contract::投影の契約;
use crate::clustered_lighting::影響半径;
use crate::cube_image::立方体の面;

pub(super) fn 遠面を指定した契約(遠面: f32) -> 投影の契約 {
    let 半径 = 影響半径::生成する(メートル::生成する(遠面)).unwrap_or_else(|誤り| panic!("検査の影響半径{遠面}を作れない: {誤り}"));
    投影の契約::影響半径から生成する(半径).unwrap_or_else(|誤り| panic!("検査の投影の契約を作れない: {誤り}"))
}

pub(super) fn 位置にする(値: [f32; 3]) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(値[0]), メートル::生成する(値[1]), メートル::生成する(値[2]))
}

/// 灯を原点に置いた契約で、表面の相対位置をその面の正規化装置座標へ写す。
pub(super) fn 面へ写す(契約: 投影の契約, 面: 立方体の面, 相対位置: [f32; 3]) -> [f32; 3] {
    let 写像 = 契約.面のライトビュー射影を組み立てる(面, 位置にする([0.0, 0.0, 0.0]));
    let 写した = 写像.適用する(位置にする(相対位置));
    [写した.x().値(), 写した.y().値(), 写した.z().値()]
}
