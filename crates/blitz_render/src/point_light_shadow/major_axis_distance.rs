//! 光から表面へ向かうベクトルの主軸の距離。触れる状態を持たず、担うのは絶対値が最大の成分を選ぶ規則だけである。
//!
//! この値が投影の契約の入口である。灯を中心とした立方体では、そのベクトルが当たる面の透視投影の奥行きが、
//! ちょうど主軸の成分の絶対値になる(前方向きとの内積が主軸の成分そのものであるため)。
//!
//! 絶対値が等しい成分が並ぶ稜線と角では、どの面を選んでも主軸の距離が同じ値になる。したがって、
//! ハードウェアの面選択がCPU正本と違う面を選んでも比較深度は一致する。この一致を`projection_contract_tests`が
//! 実測で確かめる(参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断m」)。

use blitz_math::メートル;

/// 光から表面へ向かうベクトルの、絶対値が最大の成分の大きさ。
/// 前提: 呼び出し元は有限の成分を与える(位置の差がこれを満たす)。
pub fn 光から表面へのベクトルの主軸の距離を求める(ベクトル: [f32; 3]) -> メートル {
    let 絶対値 = [ベクトル[0].abs(), ベクトル[1].abs(), ベクトル[2].abs()];
    メートル::生成する(絶対値[0].max(絶対値[1]).max(絶対値[2]))
}
