//! 点光源の影の深度の偏り。触れる状態を持たず、担うのは1つの値と、その値をどこで引くかの規約だけである。
//!
//! 多段影の1.25と1.75を流用しないのは、投影の種類が違うためである。多段影は正射影であり深度と距離が比例するのに対し、
//! 点光源の影は透視投影であり、深度の分解能が近面の近くへ寄る。深度の単位で同じ量を掛けても、世界の長さに直したときの
//! 効き方が距離によって別物になる(参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断m」)。
//!
//! そこで偏りを深度でなく世界の長さで持ち、比較深度を作る前に主軸の距離から引く。灯から遠い表面でも近い表面でも
//! 同じ長さだけ手前へずらすため、値が意味する量が距離によって変わらない。

/// 比較する主軸の距離から引く長さ(メートル)。Slangの写しは`shaders/point_light_shadow_sample.slang`にある。
///
/// 0.05にした根拠は、検収の2つの世界が持つ遮蔽物の厚み(石積みの壁が0.3メートル、小物が0.2メートル以上)より
/// 1桁小さく、遮蔽物を貫いて反対側の面を照らすことがないことと、512テクセルの1テクセルが灯から5メートルの位置で
/// 覆う長さ(およそ0.02メートル)より大きく、斜面の自己遮蔽を覆えることである。
/// 上げると接触部の影が浮き、下げると斜面に縞が出る。どちらも検収の世界の絵で判定する。
pub const 点光源の影の深度の偏りのメートル: f32 = 0.05;
