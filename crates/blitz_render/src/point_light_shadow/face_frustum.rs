//! 立方体の1つの面を灯から見たときの四角錐と、球がその内側へ届くかの判定。触れる状態を持たず、
//! 担うのは4つの側面の内向き法線の組み立てと、球の中心をその法線で測ることだけである。
//!
//! 面ごとの描画パスが描く個体を絞るためにある。可視ID列の区間を増やさずに毎フレーム絞る経路の
//! 数学の部分がここであり、絞った結果はそのフレームのコマンド記録の中だけで使う
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断n」)。
//!
//! 近面と遠面の判定を持たないのは、呼び出し元が先に灯の影響半径の球で絞るためである。同じ半径の意味を
//! 2箇所へ分けると、片方を変えたときにもう片方が古いまま残る。

use blitz_math::{メートル, ワールド, 位置};

use super::face_basis::面の直交基底を求める;
use crate::cube_image::立方体の面;

/// 灯の1つの面が覆う四角錐。頂点は灯の位置であり、縦横の開き角はどちらも90度で固定である。
#[derive(Debug, Clone, Copy)]
pub struct 面の錐台 {
    灯の位置: [f32; 3],
    /// 4つの側面の内向きの単位法線。どの平面も灯の位置を通るため、平面の定数項は持たない。
    側面の内向き法線: [[f32; 3]; 4],
}

impl 面の錐台 {
    /// 灯のカメラ相対位置と面から組み立てる。
    ///
    /// 注意: 灯の位置は描く対象と同じカメラ大域原点で狭めた値でなければならない。原点が違うと、
    /// 絞った候補と実際に描く位置が食い違う。
    pub fn 灯の位置と面から生成する(灯の位置: 位置<ワールド>, 面: 立方体の面) -> Self {
        let 基底 = 面の直交基底を求める(面);
        let 前 = 基底.前方向き();
        let 右 = 基底.右向き();
        let 上 = 基底.上向き();
        // 視野の全角が90度であるため、面の縁の向きは`前 ± 右`と`前 ± 上`である。内側の条件は
        // `|中心と右の内積| <= 中心と前の内積`とその上の版であり、これを4つの平面へ直すとこの4本になる。
        // 前と右が単位で直交するため`前 ± 右`の長さは2の平方根であり、その逆数を掛けて単位にする。
        let 単位化 = 1.0 / std::f32::consts::SQRT_2;
        Self {
            灯の位置: [灯の位置.x().値(), 灯の位置.y().値(), 灯の位置.z().値()],
            側面の内向き法線: [
                成分ごとに合成する(前, 右, -1.0, 単位化),
                成分ごとに合成する(前, 右, 1.0, 単位化),
                成分ごとに合成する(前, 上, -1.0, 単位化),
                成分ごとに合成する(前, 上, 1.0, 単位化),
            ],
        }
    }

    /// 球がこの四角錐と交わるか。中心が4つの側面のどれか1つより半径ぶんより深く外側にあれば交わらない。
    ///
    /// 保守的な判定であり、稜と角の近くでは交わらない球も交わると答える。答えが多い側へ外れるため、
    /// 描く個体が数体増えるだけで絵は変わらない(絵が変わるのは答えが少ない側へ外れたときである)。
    pub fn 球と交わるか(self, 中心: 位置<ワールド>, 半径: メートル) -> bool {
        let 灯からの中心 = [
            中心.x().値() - self.灯の位置[0],
            中心.y().値() - self.灯の位置[1],
            中心.z().値() - self.灯の位置[2],
        ];
        self.側面の内向き法線.iter().all(|法線| 内積(*法線, 灯からの中心) >= -半径.値())
    }
}

/// `甲 + 符号 × 乙`を成分ごとに作り、全体へ倍率を掛ける。
fn 成分ごとに合成する(甲: [f32; 3], 乙: [f32; 3], 符号: f32, 倍率: f32) -> [f32; 3] {
    [
        (甲[0] + 符号 * 乙[0]) * 倍率,
        (甲[1] + 符号 * 乙[1]) * 倍率,
        (甲[2] + 符号 * 乙[2]) * 倍率,
    ]
}

fn 内積(甲: [f32; 3], 乙: [f32; 3]) -> f32 {
    甲[0] * 乙[0] + 甲[1] * 乙[1] + 甲[2] * 乙[2]
}
