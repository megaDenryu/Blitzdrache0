//! 影資源添字と立方体配列の層番号の行き来の検査。24層に重なりが無いことと、往復が恒等であることを見る。

#![allow(clippy::unwrap_used)]

use std::collections::BTreeSet;

use super::capacity::{影を持てる灯の上限件数, 点光源の影の層の総数};
use super::shadow_resource_index::{層番号から影資源添字と面を求める, 影資源添字};
use crate::cube_image::立方体の全面;

/// 上限までの番号は作れ、上限に達したあとの宣言は値なしになる。
#[test]
fn 影資源添字は上限件数まで作れる() {
    for 順番 in 0..影を持てる灯の上限件数 {
        let 添字 = 影資源添字::宣言の順番から生成する(順番).unwrap();
        assert_eq!(usize::try_from(添字.値()).unwrap(), 順番);
    }
    assert_eq!(影資源添字::宣言の順番から生成する(影を持てる灯の上限件数), None);
}

/// 4件ぶん24層の描き先が重ならず、層の総数と一致する。
#[test]
fn 全ての灯と面の層番号が重ならず層の総数を埋める() {
    let mut 層一覧 = BTreeSet::new();
    for 順番 in 0..影を持てる灯の上限件数 {
        let 添字 = 影資源添字::宣言の順番から生成する(順番).unwrap();
        for 面 in 立方体の全面 {
            assert!(層一覧.insert(添字.面の層番号を求める(面)), "{順番}件目の{面:?}の層が重複した");
        }
    }
    assert_eq!(層一覧.len(), 点光源の影の層の総数);
    let 期待: BTreeSet<u32> = (0..u32::try_from(点光源の影の層の総数).unwrap()).collect();
    assert_eq!(層一覧, 期待, "層番号が0から連続して並んでいない");
}

/// 層番号から影資源添字と面を復元する往復が恒等である。
#[test]
fn 層番号と影資源添字と面の往復が恒等である() {
    for 順番 in 0..影を持てる灯の上限件数 {
        let 添字 = 影資源添字::宣言の順番から生成する(順番).unwrap();
        for 面 in 立方体の全面 {
            let 層番号 = 添字.面の層番号を求める(面);
            assert_eq!(
                層番号から影資源添字と面を求める(層番号),
                Some((添字, 面)),
                "層{層番号}の逆引きが元へ戻らない"
            );
        }
    }
}

/// 層の総数の外は値なしになる。
#[test]
fn 層の総数の外は復元できない() {
    let 総数 = u32::try_from(点光源の影の層の総数).unwrap();
    assert_eq!(層番号から影資源添字と面を求める(総数), None);
    assert_eq!(層番号から影資源添字と面を求める(総数 + 5), None);
}
