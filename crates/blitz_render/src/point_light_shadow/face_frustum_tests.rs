//! 面の錐台の判定の反証。面の正面にある球を通し、真後ろの球を落とし、縁をまたぐ球を落とさないことを見る。
//!
//! 落としてはならない球を落とすと絵から影が消えるため、通し過ぎの側(保守的)へ外れることを確かめる。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 位置};

use super::face_frustum::面の錐台;
use crate::cube_image::{立方体の全面, 立方体の面};

fn 位置を作る(成分: [f32; 3]) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(成分[0]), メートル::生成する(成分[1]), メートル::生成する(成分[2]))
}

fn 原点の錐台(面: 立方体の面) -> 面の錐台 {
    面の錐台::灯の位置と面から生成する(位置を作る([0.0, 0.0, 0.0]), 面)
}

/// 面の正面5メートルの小さい球は、その面の錐台の内側にある。
#[test]
fn 面の正面の球はその面の錐台と交わる() {
    let 組 = [
        (立方体の面::第一軸の正, [5.0, 0.0, 0.0]),
        (立方体の面::第一軸の負, [-5.0, 0.0, 0.0]),
        (立方体の面::第二軸の正, [0.0, 5.0, 0.0]),
        (立方体の面::第二軸の負, [0.0, -5.0, 0.0]),
        (立方体の面::第三軸の正, [0.0, 0.0, 5.0]),
        (立方体の面::第三軸の負, [0.0, 0.0, -5.0]),
    ];
    for (面, 中心) in 組 {
        assert!(
            原点の錐台(面).球と交わるか(位置を作る(中心), メートル::生成する(0.1)),
            "{面:?}の正面の球が交わらないと判定された"
        );
    }
}

/// 面の真後ろにある小さい球は、その面の錐台の外側にある。
#[test]
fn 面の真後ろの球はその面の錐台と交わらない() {
    let 組 = [
        (立方体の面::第一軸の正, [-5.0, 0.0, 0.0]),
        (立方体の面::第二軸の正, [0.0, -5.0, 0.0]),
        (立方体の面::第三軸の正, [0.0, 0.0, -5.0]),
    ];
    for (面, 中心) in 組 {
        assert!(
            !原点の錐台(面).球と交わるか(位置を作る(中心), メートル::生成する(0.1)),
            "{面:?}の真後ろの球が交わると判定された"
        );
    }
}

/// 灯を包む球はどの面の錐台とも交わる。灯の内側にいる個体を1つの面でも落とすと、その面だけ影が抜ける。
#[test]
fn 灯を包む球は全6面の錐台と交わる() {
    for 面 in 立方体の全面 {
        assert!(
            原点の錐台(面).球と交わるか(位置を作る([0.0, 0.0, 0.0]), メートル::生成する(3.0)),
            "{面:?}の錐台が灯を包む球を落とした"
        );
    }
}

/// 面の縁をまたぐ位置の球は、隣り合う2つの面の両方で交わると判定される。
/// 片方だけが通す形にすると、縁をまたぐ遮蔽物の影が面の境界で切れる。
#[test]
fn 面の縁をまたぐ球は隣り合う二面の両方と交わる() {
    let 中心 = 位置を作る([5.0, 0.0, 5.0]);
    let 半径 = メートル::生成する(0.5);
    assert!(
        原点の錐台(立方体の面::第一軸の正).球と交わるか(中心, 半径),
        "第一軸の正が縁の球を落とした"
    );
    assert!(
        原点の錐台(立方体の面::第三軸の正).球と交わるか(中心, 半径),
        "第三軸の正が縁の球を落とした"
    );
}

/// 灯を動かしても判定は灯からの相対で決まる。
#[test]
fn 灯を動かしても相対の位置で判定する() {
    let 錐台 = 面の錐台::灯の位置と面から生成する(位置を作る([10.0, -4.0, 7.0]), 立方体の面::第一軸の正);
    assert!(錐台.球と交わるか(位置を作る([15.0, -4.0, 7.0]), メートル::生成する(0.1)));
    assert!(!錐台.球と交わるか(位置を作る([5.0, -4.0, 7.0]), メートル::生成する(0.1)));
}
