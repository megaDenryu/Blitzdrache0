//! 比較深度の検査。近面で0・遠面で1になること、面ごとの投影が書く深度と一致すること、
//! 主軸が同値になる境界でどの面を選んでも一致することを見る。
//!
//! これが要るのは、描く側と読む側が同じ深度を出すことが影の正しさそのものだからである。
//! 片方だけが規約から外れると、接触部が浮くか影が全面でずれるかのどちらかになり、どちらも絵の中でしか現れない。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::major_axis_distance::光から表面へのベクトルの主軸の距離を求める;
use super::test_fixture::{遠面を指定した契約, 面へ写す};
use crate::cube_image::立方体の面;

/// 比較深度は近面で0、遠面で1になり、投影が書く深度と同じ値である。
#[test]
fn 比較深度が近面で0になり遠面で1になる() {
    let 契約 = 遠面を指定した契約(30.0);
    let 近 = 契約.近面().値();
    let 遠 = 契約.遠面().値();
    assert!(契約.主軸の距離から比較深度を求める(メートル::生成する(近)).abs() < 1.0e-6);
    assert!((契約.主軸の距離から比較深度を求める(メートル::生成する(遠)) - 1.0).abs() < 1.0e-6);
    for 距離 in [0.1_f32, 1.0, 7.5, 29.0] {
        let 相対位置 = [距離, 0.0, 0.0];
        let 写した = 面へ写す(契約, 立方体の面::第一軸の正, 相対位置);
        let 主軸 = 光から表面へのベクトルの主軸の距離を求める(相対位置);
        let 契約の深度 = 契約.主軸の距離から比較深度を求める(主軸);
        assert!(
            (写した[2] - 契約の深度).abs() < 1.0e-5,
            "距離{距離}で投影{}と契約{契約の深度}が食い違った",
            写した[2]
        );
    }
}

/// 絶対値が最大の成分が並ぶ稜線と角では、どの面を選んでも比較深度が同じ値になる。
/// ハードウェアの面選択がCPU正本と違う面を選んでも影が食い違わない根拠がこれである。
#[test]
fn 主軸が同値になる境界でどの面でも比較深度が一致する() {
    let 契約 = 遠面を指定した契約(40.0);
    let 組 = [
        ([6.0_f32, 6.0, 1.0], vec![立方体の面::第一軸の正, 立方体の面::第二軸の正]),
        ([-4.0, 1.0, 4.0], vec![立方体の面::第一軸の負, 立方体の面::第三軸の正]),
        (
            [5.0, 5.0, 5.0],
            vec![立方体の面::第一軸の正, 立方体の面::第二軸の正, 立方体の面::第三軸の正],
        ),
    ];
    for (相対位置, 面一覧) in 組 {
        let 契約の深度 = 契約.主軸の距離から比較深度を求める(光から表面へのベクトルの主軸の距離を求める(相対位置));
        for 面 in 面一覧 {
            let 写した = 面へ写す(契約, 面, 相対位置);
            assert!(
                (写した[2] - 契約の深度).abs() < 1.0e-5,
                "{相対位置:?}を{面:?}へ写した深度{}が契約と食い違った",
                写した[2]
            );
        }
    }
}
