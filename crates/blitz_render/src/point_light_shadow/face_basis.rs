//! 立方体の1つの面を光源から描くときの、右・上・前方の3つの向き。触れる状態を持たず、担うのは6面ぶんの表だけである。
//!
//! この表は`crates/blitz_render/src/cube_image/face_mapping.rs`の`面と面内位置から向きを求める`から導いた値であり、
//! 別の規約を新しく決めたものではない。あちらの式を`向き = 前方 + (2s - 1)×右 + (1 - 2t)×上`の形へ整理すると
//! この3つ組になる(sが面の横位置、tが面の縦位置で、どちらも0が左端・上端である)。導いた値であることを
//! `projection_contract_tests`が両者の突き合わせで確かめる。
//!
//! 注意: この3つ組は右手系ではない。右×上が前方の逆向きにならないため、これで作る変換の行列式は負になり、
//! 三角形の巻き方が反転する。描くパスはカリングを行ってはならない
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断m」)。

use blitz_math::{ワールド, 方向, 符号付きの座標軸};

use crate::cube_image::立方体の面;

/// 立方体の1つの面を描くときの、光源から見た向きの3つ組。長さはどれも1で、互いに直交する。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 面の直交基底 {
    右向き: 方向<ワールド>,
    上向き: 方向<ワールド>,
    前方向き: 方向<ワールド>,
}

impl 面の直交基底 {
    /// 3つの軸から作る。軸を符号付きの座標軸で受けるのは、面ごとの値が軸の並べ替えと符号の反転だけであり、
    /// 成分を数で書くと単位長の検査を通す手間か、到達しない失敗の枝のどちらかが要るためである。
    fn 三つの軸から生成する(右: 符号付きの座標軸, 上: 符号付きの座標軸, 前: 符号付きの座標軸) -> Self {
        Self {
            右向き: 方向::符号付きの座標軸から生成する(右),
            上向き: 方向::符号付きの座標軸から生成する(上),
            前方向き: 方向::符号付きの座標軸から生成する(前),
        }
    }

    pub fn 右向き(self) -> 方向<ワールド> {
        self.右向き
    }

    pub fn 上向き(self) -> 方向<ワールド> {
        self.上向き
    }

    /// その面が向く軸。比較深度を作る主軸の成分もこの向きとの内積である。
    pub fn 前方向き(self) -> 方向<ワールド> {
        self.前方向き
    }
}

/// 面から3つ組を引く。値は立方体画像の面の写像から導いたものであり、面ごとに軸の並べ替えと符号の反転だけを行う。
pub fn 面の直交基底を求める(面: 立方体の面) -> 面の直交基底 {
    let (右, 上, 前) = match 面 {
        立方体の面::第一軸の正 => (符号付きの座標軸::第三軸の負, 符号付きの座標軸::第二軸の正, 符号付きの座標軸::第一軸の正),
        立方体の面::第一軸の負 => (符号付きの座標軸::第三軸の正, 符号付きの座標軸::第二軸の正, 符号付きの座標軸::第一軸の負),
        立方体の面::第二軸の正 => (符号付きの座標軸::第一軸の正, 符号付きの座標軸::第三軸の負, 符号付きの座標軸::第二軸の正),
        立方体の面::第二軸の負 => (符号付きの座標軸::第一軸の正, 符号付きの座標軸::第三軸の正, 符号付きの座標軸::第二軸の負),
        立方体の面::第三軸の正 => (符号付きの座標軸::第一軸の正, 符号付きの座標軸::第二軸の正, 符号付きの座標軸::第三軸の正),
        立方体の面::第三軸の負 => (符号付きの座標軸::第一軸の負, 符号付きの座標軸::第二軸の正, 符号付きの座標軸::第三軸の負),
    };
    面の直交基底::三つの軸から生成する(右, 上, 前)
}
