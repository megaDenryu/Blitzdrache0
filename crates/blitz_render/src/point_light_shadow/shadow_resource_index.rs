//! 影付きの灯1件が使う立方体の番号と、その番号と立方体配列の層番号との行き来。
//! 触れる状態を持たず、担うのは番号が上限の内側にあることの保証と、層の割り当ての規約の保持である。
//!
//! 世界がこの番号を宣言できないようにしてあるのは、2つの灯が同じ番号を宣言した状態を型が止められないためである。
//! 作れるのは局所光源列を完成させる口だけであり、宣言の順に0から割り当てる
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断k」)。

use super::capacity::影を持てる灯の上限件数;
use crate::cube_image::立方体の面;

/// 影付きの灯1件へ割り当てた、立方体配列の中の立方体の番号。局所光レコードの影資源添字がこの値である。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 影資源添字(u32);

impl 影資源添字 {
    /// 影付きの灯を宣言の順に数えた番号から作る。上限に達したあとの灯は値なしで返し、
    /// 呼び出し元が件数と上限を添えた型付きの失敗へ写す。
    pub(crate) fn 宣言の順番から生成する(順番: usize) -> Option<Self> {
        if 順番 >= 影を持てる灯の上限件数 {
            return None;
        }
        let 値 = u32::try_from(順番).unwrap_or_else(|_| panic!("影資源添字の順番{順番}がu32に収まらない(上限の判定が破れている)"));
        Some(Self(値))
    }

    /// GPU境界(生値境界): 局所光レコードの影資源添字の欄へ書く値である。
    pub fn 値(self) -> u32 {
        self.0
    }

    /// この立方体のその面が使う、立方体配列の層番号。立方体1つが6層を連続して占める。
    pub fn 面の層番号を求める(self, 面: 立方体の面) -> u32 {
        let 面数 = u32::try_from(crate::cube_image::立方体の全面.len()).unwrap_or_else(|_| panic!("立方体の面数がu32に収まらない"));
        self.0 * 面数 + 面.層番号()
    }
}

/// 層番号から、その層を使う立方体の番号と面を復元する。`面の層番号を求める`の逆写像である。
/// 層の総数の外は値なしで返す。
pub fn 層番号から影資源添字と面を求める(層番号: u32) -> Option<(影資源添字, 立方体の面)> {
    let 面数 = u32::try_from(crate::cube_image::立方体の全面.len()).unwrap_or_else(|_| panic!("立方体の面数がu32に収まらない"));
    let 面 = 立方体の面::層番号から求める(層番号 % 面数)?;
    let 添字 = 影資源添字::宣言の順番から生成する(usize::try_from(層番号 / 面数).unwrap_or(usize::MAX))?;
    Some((添字, 面))
}
