//! 1件の影付きの灯が持つ、6面ぶんの投影の契約。触れるのは近面と遠面の2つだけであり、担うのは
//! 面ごとのライトビュー射影の組み立てと、その投影と同じ値を返す比較深度の式である。
//!
//! 描く側(頂点段が投影で写す深度)と読む側(画素段が比較のために作る深度)が同じ値を出すことが影の正しさそのものである。
//! したがって2つを別々の場所に書かず、この型が両方の出どころになる。Slangの写しは
//! `shaders/point_light_shadow_projection.slang`にある
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断m」)。

use blitz_math::{メートル, ワールド, 位置, 変換, 点光源の面クリップ};

use super::face_basis::面の直交基底を求める;
use super::input_error::点光源の影の入力エラー;
use crate::clustered_lighting::影響半径;
use crate::cube_image::立方体の面;

/// 立方体の1つの面の近面(メートル)。0にできないのは、0を入れると透視投影が退化するためである。
///
/// 0.05にした根拠は2つある。灯の器そのものより内側にある遮蔽は記録しなくてよいこと、
/// 影響半径の代表値(数メートルから数十メートル)との比が数百倍に留まり、遠くの深度の分解能を潰さないことである。
const 面の近面のメートル: f32 = 0.05;

/// 1件の影付きの灯が6面で共有する投影の契約。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 投影の契約 {
    近面: メートル,
    遠面: メートル,
}

impl 投影の契約 {
    /// その灯の影響半径から契約を作る。遠面を影響半径そのものにするのは、影響半径の外では減衰の窓が0になり、
    /// それより遠い遮蔽を記録しても絵に出ないためである。
    pub fn 影響半径から生成する(影響半径: 影響半径) -> Result<Self, 点光源の影の入力エラー> {
        let 近面 = メートル::生成する(面の近面のメートル);
        let 遠面 = 影響半径.長さ();
        if 遠面.値() <= 近面.値() {
            return Err(点光源の影の入力エラー::影響半径が近面以下 {
                影響半径: 遠面.値(),
                近面: 近面.値(),
            });
        }
        Ok(Self { 近面, 遠面 })
    }

    pub fn 近面(self) -> メートル {
        self.近面
    }

    pub fn 遠面(self) -> メートル {
        self.遠面
    }

    /// 主軸の距離から、シャドウマップの深度と比べるための深度を作る。近面で0、遠面で1になる順Zの値である。
    ///
    /// 式は`遠面 × (距離 - 近面) / (距離 × (遠面 - 近面))`であり、面の透視投影の第3行から導いた。
    /// 近面より手前の距離では負の値を返す。負の値は必ず比較に通るため、灯のすぐそばの表面は影に落ちない。
    pub fn 主軸の距離から比較深度を求める(self, 主軸の距離: メートル) -> f32 {
        let 距離 = 主軸の距離.値();
        let 近 = self.近面.値();
        let 遠 = self.遠面.値();
        遠 * (距離 - 近) / (距離 * (遠 - 近))
    }

    /// その面を描くときのライトビュー射影を、灯のカメラ相対位置を視点にして組み立てる。
    /// 注意: 呼び出し元は描く対象と同じカメラ大域原点で狭めた位置を渡す責務を負う。
    pub fn 面のライトビュー射影を組み立てる(
        self,
        面: 立方体の面,
        灯のカメラ相対位置: 位置<ワールド>,
    ) -> 変換<ワールド, 点光源の面クリップ> {
        let 基底 = 面の直交基底を求める(面);
        let 視 = 変換::立方体の面の基底から生成する(灯のカメラ相対位置, 基底.右向き(), 基底.上向き(), 基底.前方向き());
        視.合成する(変換::立方体の面の透視投影(self.近面, self.遠面))
    }
}
