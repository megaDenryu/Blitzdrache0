//! 世界が宣言した時間再構成方式の、描画側での表し方。担うのは「履歴画像を読むパスがそのフレームへ積まれるか」
//! という1つの判定だけである。
//!
//! 間接照明方針・露出方式・拡散間接方式と独立の軸にするのは、時間再構成が画の完成のあとに掛かる時間方向の
//! 平均化であって、照度の供給元でも表面の陰りでもないためである。
//!
//! 資源とパイプラインの形はこの方式で変えない。動きベクトル画像と履歴画像は方式に依らず同じ寸法・同じ形式で
//! 確保し、シーン描画と空のパスは方式に依らず動きベクトルを書く。方式で分かれるのは時間再構成のパスを積むか
//! どうかと、履歴画像へ初期値を書き込むかどうかだけである
//! (`参照: _doc/設計/時間再構成.md`「判断e: 世界宣言の第4軸と検収の保護」)。

/// 世界が宣言する時間再構成の方式。CPU正本は`blitz_engine::temporal_reconstruction::時間再構成方式`であり、
/// コンポジションルートがその値を開いてここへ写す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 時間再構成方式 {
    /// 今のフレームの結果をそのまま出す。過去のフレームの色を1画素も読まない。
    使わない,
    /// 動きベクトルで写した前のフレームの色を今のフレームの色へ混ぜる。
    履歴混合,
}

impl 時間再構成方式 {
    /// 履歴画像を読むパスがそのフレームへ積まれるか。確保したばかりの画像の中身は不定であるため、
    /// 読むパスが積まれる方式でだけ確保の直後に既知の値を書き込む必要がある。
    pub(crate) fn 履歴画像を読むパスが積まれるか(self) -> bool {
        matches!(self, Self::履歴混合)
    }
}
