//! 描画束ID: まとめて追加・解除される描画対象の束を、呼び出し元が区別するための番号。
//!
//! レンダラーはこの番号の意味を知らない。世界のどの区画かという解釈は呼び出し元が持ち、
//! レンダラーは「同じ番号なら同じ束」という同一性だけを使う。番号の意味をレンダラーが知ると、
//! 特定の絵の分割方針が描画レイヤーへ流れ込む(参照: `_doc/設計/機能配置の指針.md`「レイヤーの責務」)。

use crate::cascade::距離区分番号;
use crate::visible_instance_selection::可視パス;

/// 呼び出し元が決めた番号で束を区別する識別子。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct 描画束ID(u64);

impl 描画束ID {
    /// レンダラーにとって番号は不透明であり、すべてのu64が有効な識別子である。
    pub const fn 生成する(番号: u64) -> Self {
        Self(番号)
    }

    /// ログと呼び出し元との突き合わせに使う番号を返す。
    pub fn 番号を返す(self) -> u64 {
        self.0
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 描画束の影方針 {
    全距離区分,
    最遠距離区分だけ,
}

impl 描画束の影方針 {
    pub(crate) fn パスを描くか(self, パス: 可視パス) -> bool {
        match (self, パス) {
            (_, 可視パス::シーン) | (Self::全距離区分, 可視パス::影の距離区分(_)) => true,
            (Self::最遠距離区分だけ, 可視パス::影の距離区分(距離区分番号::距離区分3)) => true,
            (Self::最遠距離区分だけ, 可視パス::影の距離区分(_)) => false,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 最遠だけはシーンと距離区分3だけを通す() {
        let 方針 = 描画束の影方針::最遠距離区分だけ;
        assert!(方針.パスを描くか(可視パス::シーン));
        assert!(!方針.パスを描くか(可視パス::影の距離区分(距離区分番号::距離区分0)));
        assert!(!方針.パスを描くか(可視パス::影の距離区分(距離区分番号::距離区分1)));
        assert!(!方針.パスを描くか(可視パス::影の距離区分(距離区分番号::距離区分2)));
        assert!(方針.パスを描くか(可視パス::影の距離区分(距離区分番号::距離区分3)));
    }
}
