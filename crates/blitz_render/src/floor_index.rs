//! 実数の位置以下で最大の添字を、範囲の外を端へ張り付けたうえで求める工程。受け取るのは実数の位置と添字の上限、
//! 返すのは0から上限までに収まる添字である。
//!
//! 二分探索で求めるのは、浮動小数から整数への安全な標準変換が無く(`as`キャストは規約で禁止)、
//! 文字列往復による丸めはテクセルごとに何度も呼ぶ経路には遅すぎるためである。辺の長さは1024以下であり、
//! 比較は10回程度で終わる。
//!
//! クレートの根へ置くのは、大気の表の双一次補間と遠方環境の派生表現の立方体テクセルの参照という、
//! 別のモジュール木にある2つの利用者が同じ規則を要るためである。

/// 位置以下で最大の添字。非数と負は0へ、上限より大きい位置は上限へ張り付ける。
pub(crate) fn 実数位置の床の添字(位置: f64, 最大添字: u32) -> u32 {
    if 位置.is_nan() || 位置 <= 0.0 {
        return 0;
    }
    if 位置 >= f64::from(最大添字) {
        return 最大添字;
    }
    let mut 下 = 0u32;
    let mut 上 = 最大添字;
    while 下 < 上 {
        let 中 = 下 + (上 - 下).div_ceil(2);
        if f64::from(中) <= 位置 {
            下 = 中;
        } else {
            上 = 中 - 1;
        }
    }
    下
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::実数位置の床の添字;

    #[test]
    fn 範囲の中の位置は床を返す() {
        assert_eq!(実数位置の床の添字(3.9, 10), 3);
        assert_eq!(実数位置の床の添字(4.0, 10), 4);
    }

    #[test]
    fn 範囲の外は端へ張り付ける() {
        assert_eq!(実数位置の床の添字(-1.0, 10), 0);
        assert_eq!(実数位置の床の添字(99.0, 10), 10);
        assert_eq!(実数位置の床の添字(f64::NAN, 10), 0);
    }
}
