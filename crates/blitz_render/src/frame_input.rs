/// 1フレームに描くものと、その描き方を決める値の組。
///
/// `空`・`大気`・`遠方環境`・`スキン行列一覧`・`布`は、それぞれの資源を持つレンダラーでは毎フレーム必須であり、
/// 有無が資源の有無と一致しないと描画は型付きエラーになる。無言で省くことも、既定の姿勢や値を当てることもしない。
/// `空`と`大気`を別に持つのは、片方が時刻から導く解析近似の係数、もう片方が時刻に依存しない大気そのものであり、
/// 作り直す条件が違うためである(参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「大気のベイク済み画像方式の設計(第7段で実装する)」)。
/// `遠方環境`を`大気`と別に持つのも同じ理由であり、遠方環境キーは太陽放射照度と夜空放射輝度も見る。
///
/// `露出`はポストプロセス無効時、`自動露出の経過秒`は露出方式が時刻別固定の世界では使われない。後者の適応速度が
/// 「補正段毎秒」であるため、実時間で進む実行と固定の刻みで進む実行のどちらであるかは呼び出し元が決め、
/// レンダラーは渡された秒をそのまま使う。
///
/// `影のキャスター`の`全て外す`は添付処理の切片を測る対照であり、`画素診断`の診断の枝は検収が画素から読み取る
/// ための補助である。絵の最終判定は本番の色で行う。`ui描画`が`None`ならUIパス自体をグラフへ積まない
/// (判断34: 既定オフ時は既存スモークの厳密判定を無傷に保つ)。
///
/// `地形詳細段選択一覧`の段の選択はGPU資源の確保も解放も伴わず、描画入力へ積む幾何を選ぶだけである
/// (参照: `_doc/設計/地形とカメラ相対描画.md`「LOD」)。所有せず借用で受けるのは、常駐束数ぶんのVecを毎フレーム
/// 確保して直後に破棄することを避けるためである。`可視個体選択一覧`の段の区間はパスごとに別々の開始と描画数を
/// 持ち、シーンはカメラ視錐台、距離区分0から距離区分3はその距離区分のライト視錐台の判定結果である
/// (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」)。
///
/// `動く個体の大域の位置と向きの指定一覧`が宣言していない個体を指すと型付きエラーになる(無言で捨てると、供給して
/// いるのに動かない状態が絵にしか出ない)。型で強制されるのはこの供給→宣言の向きだけであり、宣言済みの個体への
/// 供給漏れは前フレームの位置のまま描かれる(供給と宣言を同じ台帳から作る呼び出し側の規律が防ぐ)。宣言を1つも
/// 持たない起動ではこの一覧が常に空であり、動く個体の書き込みは1件も起こらない。
/// `プリミティブ発行`は段の選択で選ばれた詳細段のプリミティブだけが発行になり、ここに無い描画対象は描く
/// インデックス区間を決められないため、描画は型付きエラーになる(無言で対象を飛ばすことはしない)。可視選別は
/// 個体・原型・詳細段について1回だけ行い、プリミティブへの展開はその結果を読むこの段でだけ起こる
/// (参照: `_doc/設計/マルチマテリアルと材質境界.md`「可視ID列の契約」)。
#[derive(Debug, Clone)]
pub struct フレーム描画入力<'a> {
    pub クリア色: クリアカラー,
    pub 視点一覧: 描画視点一覧, // 非空の一覧。通常画面も要素数1として表す
    pub ライティング: ライティング入力,
    pub 空: Option<空入力>,                                                           // 空パスの1フレーム入力
    pub 大気: Option<大気のベイク済み画像の入力>,                                     // 大気のベイク済み画像を作る入力
    pub 遠方環境: Option<遠方環境の入力>,                                             // 遠方環境と派生表現を焼く入力
    pub 露出: f32,                                                                    // 明るさの圧縮前にHDR輝度へ掛ける露出倍率(判断39)
    pub 自動露出の経過秒: f32,                                                        // 自動露出の時間適応が進む秒数
    pub 影のキャスター: 影のキャスター指定,                                           // シャドウパスへ描画入力を積むか。既定は`通常に描く`
    pub 画素診断: crate::cascade::画素診断,     // シーンの画素段が本番の色の代わりに何を出すか。既定は`出さない`
    pub スキン行列一覧: Option<Vec<[f32; 16]>>, // ジョイントごとの列優先4x4(判断44)
    pub 布: Option<布フレーム入力>,             // 布シミュレーションの毎フレーム入力(判断52〜54)
    pub ui描画: Option<UI描画データ>,           // 開発用UI(egui)の今フレームぶんの描画データ
    pub 地形詳細段選択一覧: &'a [地形詳細段選択], // 束ごとに描く地形の詳細段。ここに無い束は最詳細段を描く
    pub 可視個体選択一覧: 可視個体選択一覧<'a>, // 各パスが描く個体の選択。ここに無い描画対象は全個体を描く
    pub 動く個体の大域の位置と向きの指定一覧: &'a [動く個体の大域の位置と向きの指定], // 大域の位置と、読込時の姿勢から回す向き
    pub プリミティブ発行: &'a プリミティブ発行受け皿, // 描画対象ごとの、その対象が描くプリミティブの並び
}

/// 布シミュレーションの1フレーム入力(判断53・54)。カプセルはキャラクター近似1本、
/// 介入バイト列のレイアウトはshaders/cloth_step.slangの介入仕様(32バイト/件)と一致させる。
#[derive(Debug, Clone)]
pub struct 布フレーム入力 {
    pub カプセル端点a: [f32; 3],
    pub カプセル端点b: [f32; 3],
    pub カプセル半径: f32,
    pub 介入バイト列: Vec<u8>,
    pub 介入件数: u32,
}
