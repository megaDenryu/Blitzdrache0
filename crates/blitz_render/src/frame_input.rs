//! 1フレーム描画の入力をまとめた値オブジェクト(判断24)。
//! 視点・ライティング・シミュレーションの入力を増やしても引数列を拡散させないため、
//! `一フレーム描画する`系のAPIはこの1つの入力にまとめる。

use crate::clear_color::クリアカラー;
use crate::lighting_input::ライティング入力;
use crate::terrain_detail::地形詳細段選択;
use crate::ui_draw_data::UI描画データ;
use crate::view_input::描画視点一覧;

#[derive(Debug, Clone)]
pub struct フレーム描画入力<'a> {
    pub クリア色: クリアカラー,
    /// 1フレームで描画する非空の視点一覧。通常画面も要素数1として表す。
    pub 視点一覧: 描画視点一覧,
    pub ライティング: ライティング入力,
    /// トーンマッピング前にHDR輝度へ掛ける露出倍率(判断39)。ポストプロセス無効時は使われない。
    pub 露出: f32,
    /// スキン行列一覧(ジョイントごとの列優先4x4。判断44)。スキン付きシーンでは毎フレーム必須で、
    /// 有無がレンダラーのスキンメッシュと一致しないと描画は型付きエラーになる(無言のデフォルト姿勢は適用しない)。
    pub スキン行列一覧: Option<Vec<[f32; 16]>>,
    /// 布シミュレーションの毎フレーム入力(判断52〜54)。布付きレンダラーでは毎フレーム必須で、
    /// 有無が布資源の有無と一致しないと描画は型付きエラーになる。
    pub 布: Option<布フレーム入力>,
    /// 開発用UI(egui)の今フレームぶんの描画データ。`None`ならUIパス自体を
    /// グラフへ積まない(判断34: 既定オフ時は既存スモークの厳密判定を無傷に保つ)。
    pub ui描画: Option<UI描画データ>,
    /// 束ごとに描く地形の詳細段。ここに無い束は最詳細段を描く。段の選択はGPU資源の確保も解放も伴わず、
    /// 描画入力へ積む幾何を選ぶだけである(参照: `_doc/設計/地形とカメラ相対描画.md`「LOD」)。
    /// 所有せず借用で受けるのは、常駐束数ぶんのVecを毎フレーム確保して直後に破棄することを避けるためである。
    pub 地形詳細段選択一覧: &'a [地形詳細段選択],
}

/// 布シミュレーションの1フレーム入力(判断53・54)。カプセルはキャラクター近似1本、
/// 介入バイト列のレイアウトはshaders/cloth_step.slangの介入仕様(32バイト/件)と一致させる。
#[derive(Debug, Clone)]
pub struct 布フレーム入力 {
    pub カプセル端点a: [f32; 3],
    pub カプセル端点b: [f32; 3],
    pub カプセル半径: f32,
    pub 介入バイト列: Vec<u8>,
    pub 介入件数: u32,
}
