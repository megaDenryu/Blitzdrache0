//! 1フレーム描画の入力をまとめた値オブジェクト(判断24)。
//! 視点・ライティング・シミュレーションの入力を増やしても引数列を拡散させないため、
//! `一フレーム描画する`系のAPIはこの1つの入力にまとめる。
//! クレート根へ再輸出するのは`一フレーム描画する`が直に受け取る型だけであり、呼び出し元が保持して使い回すプリミティブ発行の器は
//! このモジュールの名前で参照する。根の名前を増やすほど、どれが1フレームの入力なのかが読めなくなるためである。

use crate::atmosphere_lut_input::大気のベイク済み画像の入力;
use crate::clear_color::クリアカラー;
use crate::distant_environment::遠方環境の入力;
mod primitive_issue;
mod primitive_issue_section;
mod primitive_issue_tray;
mod shadow_casters;
mod sky_input;

pub use primitive_issue::プリミティブ描画発行;
pub use primitive_issue_tray::プリミティブ発行受け皿;
pub use shadow_casters::影のキャスター指定;
pub use sky_input::{空入力, 空入力の材料, 空入力エラー};

use crate::lighting_input::ライティング入力;
use crate::terrain_detail::地形詳細段選択;
use crate::ui_draw_data::UI描画データ;
use crate::view_input::描画視点一覧;
use crate::visible_instance_selection::可視個体選択一覧;

#[derive(Debug, Clone)]
pub struct フレーム描画入力<'a> {
    pub クリア色: クリアカラー,
    /// 1フレームで描画する非空の視点一覧。通常画面も要素数1として表す。
    pub 視点一覧: 描画視点一覧,
    pub ライティング: ライティング入力,
    /// 空パスの1フレーム入力。フレーム構成に空段階があるレンダラーでは毎フレーム必須で、
    /// 有無が空パス資源の有無と一致しないと描画は型付きエラーになる(無言で空を省くことはしない)。
    pub 空: Option<空入力>,
    /// 大気のベイク済み画像を作る入力。空を持つ世界では毎フレーム必須で、有無が大気のベイク済み画像資源の有無と一致しないと描画は型付きエラーになる。
    /// 空入力と別に持つのは、片方が時刻から導く解析近似の係数、もう片方が時刻に依存しない大気そのものであり、
    /// 作り直す条件が違うためである(参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「大気のベイク済み画像方式の設計(第7段で実装する)」)。
    pub 大気: Option<大気のベイク済み画像の入力>,
    /// 遠方環境と派生表現を焼く入力。照明問い合わせ契約が遠方環境の枝のレンダラーでは毎フレーム必須で、
    /// 有無が遠方環境の照明資源の有無と一致しないと描画は型付きエラーになる。大気の入力と別に持つのは、
    /// 焼き直す条件が違うためである(遠方環境キーは太陽放射照度と夜空放射輝度も見る)。
    pub 遠方環境: Option<遠方環境の入力>,
    /// 明るさの圧縮前にHDR輝度へ掛ける露出倍率(判断39)。ポストプロセス無効時は使われない。
    pub 露出: f32,
    /// 自動露出の時間適応が進む秒数。適応速度が「補正段毎秒」であるため、実時間で進む実行と固定の刻みで進む実行の
    /// どちらであるかは呼び出し元が決め、レンダラーは渡された秒をそのまま使う。露出方式が時刻別固定の世界では使われない。
    pub 自動露出の経過秒: f32,
    /// そのフレームのシャドウパスへ描画入力を積むか。既定は`通常に描く`であり、`全て外す`は添付処理の切片を測る対照である。
    pub 影のキャスター: 影のキャスター指定,
    /// シーンの画素段が本番の色の代わりに何を出すか。既定は`出さない`であり、診断の枝は検収が画素から読み取るための補助である。
    /// 絵の最終判定は本番の色で行う。
    pub 画素診断: crate::cascade::画素診断,
    /// スキン行列一覧(ジョイントごとの列優先4x4。判断44)。スキン付きシーンでは毎フレーム必須で、
    /// 有無がレンダラーのスキンメッシュと一致しないと描画は型付きエラーになる(無言のデフォルト姿勢は適用しない)。
    pub スキン行列一覧: Option<Vec<[f32; 16]>>,
    /// 布シミュレーションの毎フレーム入力(判断52〜54)。布付きレンダラーでは毎フレーム必須で、
    /// 有無が布資源の有無と一致しないと描画は型付きエラーになる。
    pub 布: Option<布フレーム入力>,
    /// 開発用UI(egui)の今フレームぶんの描画データ。`None`ならUIパス自体を
    /// グラフへ積まない(判断34: 既定オフ時は既存スモークの厳密判定を無傷に保つ)。
    pub ui描画: Option<UI描画データ>,
    /// 束ごとに描く地形の詳細段。ここに無い束は最詳細段を描く。段の選択はGPU資源の確保も解放も伴わず、
    /// 描画入力へ積む幾何を選ぶだけである(参照: `_doc/設計/地形とカメラ相対描画.md`「LOD」)。
    /// 所有せず借用で受けるのは、常駐束数ぶんのVecを毎フレーム確保して直後に破棄することを避けるためである。
    pub 地形詳細段選択一覧: &'a [地形詳細段選択],
    /// そのフレームに各パスが描く個体の選択。ここに無い描画対象は全個体を描く。
    /// 段の区間はパスごとに別々の開始と描画数を持ち、シーンはカメラ視錐台、距離区分0から距離区分3はその距離区分のライト視錐台の判定結果である
    /// (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」)。
    pub 可視個体選択一覧: 可視個体選択一覧<'a>,
    /// 描画対象ごとに、その対象が描くプリミティブの並び。段の選択で選ばれた詳細段のプリミティブだけが発行になる。
    /// ここに無い描画対象は描くインデックス区間を決められないため、描画は型付きエラーになる(無言で対象を飛ばすことはしない)。
    /// 可視選別は個体・原型・詳細段について1回だけ行い、プリミティブへの展開はその結果を読むこの段でだけ起こる
    /// (参照: `_doc/設計/マルチマテリアルと材質境界.md`「可視ID列の契約」)。
    pub プリミティブ発行: &'a プリミティブ発行受け皿,
}

/// 布シミュレーションの1フレーム入力(判断53・54)。カプセルはキャラクター近似1本、
/// 介入バイト列のレイアウトはshaders/cloth_step.slangの介入仕様(32バイト/件)と一致させる。
#[derive(Debug, Clone)]
pub struct 布フレーム入力 {
    pub カプセル端点a: [f32; 3],
    pub カプセル端点b: [f32; 3],
    pub カプセル半径: f32,
    pub 介入バイト列: Vec<u8>,
    pub 介入件数: u32,
}
