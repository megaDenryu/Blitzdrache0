//! 位置の不変装飾を付けられなかったときの失敗。担当するのは、付けられない理由を呼び出し元が枝で見分けられる形にすることである。
//!
//! 枝を3つに分けるのは、原因ごとに直す場所が違うためである。語として読めないのはコンパイラの出力が壊れている状態、
//! 位置の組み込み出力が無いのは頂点段でないSPIR-Vを渡した状態であり、前者はシェーダーの生成、後者は呼び出し側の取り違えを指す。

use thiserror::Error;

#[derive(Debug, Error, Clone, Copy, PartialEq, Eq)]
pub enum 位置の不変装飾エラー {
    #[error("SPIR-Vのバイト長が語の並びとして読めない: {0}バイト")]
    語の並びとして読めない(usize),

    #[error("SPIR-Vの魔法数が合わない: {0:#x}")]
    魔法数が合わない(u32),

    #[error("SPIR-Vに位置の組み込み出力の宣言が無い(頂点段のSPIR-Vではない)")]
    位置の組み込み出力が無い,
}
