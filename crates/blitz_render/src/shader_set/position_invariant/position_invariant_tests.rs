//! 位置の不変装飾を付ける工程の検査。合成した語の並びで、装飾が1つ増えること・二重に増えないこと・付けられない入力を型付きで落とすことを見る。

#![allow(clippy::unwrap_used)]

use super::*;

const 魔法数: u32 = 0x0723_0203;

/// 位置の組み込み出力を1つ宣言しただけの語の並び。ヘッダ5語の後ろにOpDecorateが1本並ぶ。
fn 位置の宣言だけを持つ語の並び() -> Vec<u32> {
    vec![
        魔法数,
        0x0001_0500,
        0,
        10,
        0,
        (4 << 16) | u32::from(命令_OP_DECORATE),
        7,
        装飾_BUILT_IN,
        組み込み_POSITION,
    ]
}

fn バイト列へ(語一覧: &[u32]) -> Vec<u8> {
    語一覧.iter().flat_map(|語| 語.to_le_bytes()).collect()
}

fn 語へ(バイト列: &[u8]) -> Vec<u32> {
    バイト列
        .chunks_exact(4)
        .map(|塊| u32::from_le_bytes([塊[0], 塊[1], 塊[2], 塊[3]]))
        .collect()
}

#[test]
fn 位置の宣言の直後へ不変装飾が1本増える() {
    let 結果 = 位置の不変装飾を付ける(&バイト列へ(&位置の宣言だけを持つ語の並び())).unwrap();
    let 語一覧 = 語へ(&結果);
    assert_eq!(語一覧.len(), 9 + 3);
    assert_eq!(語一覧[9], (3 << 16) | u32::from(命令_OP_DECORATE));
    assert_eq!(語一覧[10], 7);
    assert_eq!(語一覧[11], 装飾_INVARIANT);
}

#[test]
fn 既に付いている並びは語の数が変わらない() {
    let 一度目 = 位置の不変装飾を付ける(&バイト列へ(&位置の宣言だけを持つ語の並び())).unwrap();
    let 二度目 = 位置の不変装飾を付ける(&一度目).unwrap();
    assert_eq!(一度目, 二度目);
}

#[test]
fn 位置の宣言が無い並びは型付きで落ちる() {
    let 語一覧 = vec![魔法数, 0x0001_0500, 0, 10, 0];
    assert_eq!(
        位置の不変装飾を付ける(&バイト列へ(&語一覧)),
        Err(位置の不変装飾エラー::位置の組み込み出力が無い)
    );
}

#[test]
fn 語として読めない入力と魔法数違いは別の枝で落ちる() {
    assert_eq!(位置の不変装飾を付ける(&[0, 1, 2]), Err(位置の不変装飾エラー::語の並びとして読めない(3)));
    let 語一覧 = vec![0xDEAD_BEEF_u32, 0, 0, 0, 0];
    assert_eq!(
        位置の不変装飾を付ける(&バイト列へ(&語一覧)),
        Err(位置の不変装飾エラー::魔法数が合わない(0xDEAD_BEEF))
    );
}
