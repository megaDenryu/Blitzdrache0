//! 装飾の並びの読み取り。受け取るのは語の並びと命令の範囲の並び、返すのは位置の組み込み出力の宣言と、そのidへ既に不変装飾が付いているかである。
//!
//! 読み取りを挿し込みと分けるのは、挿し込みの前に「どのidへ」「どこへ」「そもそも要るのか」の3つが決まっていなければならないためである。
//! OpDecorateの被演算子は[対象id, 装飾, 追加の値...]の順に並ぶ。

use super::word_stream::命令の範囲;
use super::{命令_OP_DECORATE, 組み込み_POSITION, 装飾_BUILT_IN, 装飾_INVARIANT};

/// 位置の組み込み出力として装飾された変数と、その宣言が終わる語の位置。
#[derive(Clone, Copy)]
pub(super) struct 位置の宣言 {
    pub(super) 変数id: u32,
    /// この宣言の直後の語位置。装飾を足すときはここへ挿し込む。
    pub(super) 直後の語位置: usize,
}

pub(super) fn 位置の宣言を探す(語一覧: &[u32], 命令一覧: &[命令の範囲]) -> Option<位置の宣言> {
    命令一覧.iter().filter(|範囲| 範囲.命令コード == 命令_OP_DECORATE).find_map(|範囲| {
        let 被演算子 = 範囲.被演算子(語一覧);
        let 位置の組み込みか = 被演算子.len() >= 3 && 被演算子[1] == 装飾_BUILT_IN && 被演算子[2] == 組み込み_POSITION;
        位置の組み込みか.then(|| 位置の宣言 {
            変数id: 被演算子[0],
            直後の語位置: 範囲.終了,
        })
    })
}

/// そのidへ不変装飾が既に付いているか。
pub(super) fn 不変装飾が付いているか(語一覧: &[u32], 命令一覧: &[命令の範囲], 対象id: u32) -> bool {
    命令一覧
        .iter()
        .filter(|範囲| 範囲.命令コード == 命令_OP_DECORATE)
        .map(|範囲| 範囲.被演算子(語一覧))
        .any(|被演算子| 被演算子.len() >= 2 && 被演算子[0] == 対象id && 被演算子[1] == 装飾_INVARIANT)
}
