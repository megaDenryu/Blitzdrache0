//! 幅と高さがともに1以上であることを検証済みのウィンドウ寸法を表す値オブジェクト。

use super::ウィンドウ寸法;

/// スワップチェーンを作れる寸法だけを表す型。生成時の検証を通った値しかこの型にならないため、
/// この型を要求する側はゼロ寸法（Windowsが最小化時に送る寸法）を受け取りえない。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 非ゼロ寸法(ウィンドウ寸法);

impl 非ゼロ寸法 {
    /// 幅・高さのどちらかが0なら生成しない。呼び出し側はこの`None`で最小化を判別する。
    pub(crate) fn 生成する(寸法: ウィンドウ寸法) -> Option<Self> {
        if 寸法.ゼロ寸法か() { None } else { Some(Self(寸法)) }
    }

    /// スワップチェーン生成へ渡すためにウィンドウ寸法へ戻す。
    pub(crate) fn ウィンドウ寸法へ(&self) -> ウィンドウ寸法 {
        self.0
    }
}
