//! 大気LUTのGPU読み戻し検査の公開入口。担当するのは「ウィンドウを持たないGPUで2枚のLUTを焼き、
//! 中身を生の4成分で返す」ことである。呼び出し元は検収コマンドだけであり、本番の描画経路はここを通らない。
//!
//! 検証済みの値オブジェクトでなく生の4成分を返すのは、検査が非有限値や負の値を観測できなければならないためである。
//! 検証済みの型で返すと、まさに検査したい壊れた値が構築の時点で弾かれ、GPU側の欠陥が見えなくなる。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「検証」

use crate::atmosphere::{大気LUT解像度, 大気散乱媒体};
use crate::error::レンダラーエラー;
use crate::shader_bundle::大気LUTシェーダー一式;
use crate::validation_counter::検証層の状況;
use crate::vulkan::atmosphere_lut;

/// GPUが焼いた2枚のLUTの中身と、その実行のvalidationの観測。並びは行優先であり、CPU正本が焼く並びと一致する。
/// 4成分目はシェーダーが予約として0を書くため、読む側はRGBの3成分だけを見る。
///
/// validationの観測を中身と同じ型で返すのは、この検査が「値が正しい」と「Vulkanの使い方が正しい」の両方を
/// 見る1つの入口だからである。片方だけを返す形にすると、呼び出し元が層の在否を報告しないことを許してしまう。
pub struct 大気LUT読み戻し {
    透過率: Vec<[f32; 4]>,
    多重散乱: Vec<[f32; 4]>,
    検証層の状況: 検証層の状況,
    検証件数: u64,
}

impl 大気LUT読み戻し {
    pub fn 透過率(&self) -> &[[f32; 4]] {
        &self.透過率
    }

    pub fn 多重散乱(&self) -> &[[f32; 4]] {
        &self.多重散乱
    }

    /// validation層を有効にできたかどうか。件数0が保証になるのは有効だった実行だけである。
    pub fn 検証層の状況(&self) -> 検証層の状況 {
        self.検証層の状況
    }

    /// validation層がこの実行で数えたエラー・警告の合計件数。インスタンス破棄までの全指摘を含む。
    pub fn 検証件数(&self) -> u64 {
        self.検証件数
    }
}

/// ウィンドウもスワップチェーンも作らずにGPUを初期化し、本番と同じパス宣言で2枚のLUTを焼いて読み戻す。
/// 送信は1回で、戻った時点でGPUの作業は完了している。
pub fn 大気lutをgpuで焼いて読み戻す(
    媒体: &大気散乱媒体,
    解像度: 大気LUT解像度,
    シェーダー: &大気LUTシェーダー一式,
) -> Result<大気LUT読み戻し, レンダラーエラー> {
    let (読み戻し, 検証) = atmosphere_lut::大気lutをgpuで焼いて読み戻す(媒体, 解像度, シェーダー)?;
    Ok(大気LUT読み戻し {
        透過率: 読み戻し.透過率,
        多重散乱: 読み戻し.多重散乱,
        検証層の状況: 検証.状況,
        検証件数: 検証.件数,
    })
}
