//! 大気のベイク済み画像のGPU読み戻し検査の公開入口。担当するのは「ウィンドウを持たないGPUで3枚のベイク済み画像を焼き、
//! 中身を生の4成分で返す」ことである。呼び出し元は検収コマンドだけであり、本番の描画経路はここを通らない。
//!
//! 検証済みの値オブジェクトでなく生の4成分を返すのは、検査が非有限値や負の値を観測できなければならないためである。
//! 検証済みの型で返すと、まさに検査したい壊れた値が構築の時点で弾かれ、GPU側の欠陥が見えなくなる。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「検証」

use crate::atmosphere::{スカイビュー観測条件, 大気のベイク済み画像の解像度, 大気散乱媒体, 空中遠近観測条件};
use crate::error::レンダラーエラー;
use crate::shader_bundle::大気のベイク済み画像のシェーダー一式;
use crate::validation_counter::検証層の状況;
use crate::vulkan::atmosphere_lut;

/// GPUが焼いた3枚のベイク済み画像の中身と、その実行のvalidationの観測。並びは行優先であり、CPU正本が焼く並びと一致する。
/// 4成分目はシェーダーが予約として0を書くため、読む側はRGBの3成分だけを見る。
///
/// validationの観測を中身と同じ型で返すのは、この検査が「値が正しい」と「Vulkanの使い方が正しい」の両方を
/// 見る1つの入口だからである。片方だけを返す形にすると、呼び出し元が層の在否を報告しないことを許してしまう。
pub struct 大気のベイク済み画像の読み戻し {
    透過率: Vec<[f32; 4]>,
    多重散乱: Vec<[f32; 4]>,
    スカイビュー: Vec<[f32; 4]>,
    空中遠近: Vec<[f32; 4]>,
    検証層の状況: 検証層の状況,
    検証件数: u64,
}

impl 大気のベイク済み画像の読み戻し {
    pub fn 透過率(&self) -> &[[f32; 4]] {
        &self.透過率
    }

    pub fn 多重散乱(&self) -> &[[f32; 4]] {
        &self.多重散乱
    }

    pub fn スカイビュー(&self) -> &[[f32; 4]] {
        &self.スカイビュー
    }

    /// 空中遠近ボリュームの中身。並びは横が最も速く、次に縦、最後に奥である。
    /// 4成分目は予約でなく代表透過率であり、読む側はRGBとAの4成分すべてを見る。
    pub fn 空中遠近(&self) -> &[[f32; 4]] {
        &self.空中遠近
    }

    /// validation層を有効にできたかどうか。件数0が保証になるのは有効だった実行だけである。
    pub fn 検証層の状況(&self) -> 検証層の状況 {
        self.検証層の状況
    }

    /// validation層がこの実行で数えたエラー・警告の合計件数。インスタンス破棄までの全指摘を含む。
    pub fn 検証件数(&self) -> u64 {
        self.検証件数
    }
}

/// ウィンドウもスワップチェーンも作らずにGPUを初期化し、本番と同じパス宣言で3枚のベイク済み画像を焼いて読み戻す。
/// 送信は1回で、戻った時点でGPUの作業は完了している。
pub fn 大気のベイク済み画像をgpuで焼いて読み戻す(
    媒体: &大気散乱媒体,
    解像度: 大気のベイク済み画像の解像度,
    スカイビュー条件: スカイビュー観測条件,
    空中遠近条件: 空中遠近観測条件,
    シェーダー: &大気のベイク済み画像のシェーダー一式,
) -> Result<大気のベイク済み画像の読み戻し, レンダラーエラー> {
    let (読み戻し, 検証) = atmosphere_lut::大気のベイク済み画像をgpuで焼いて読み戻す(atmosphere_lut::焼く条件 {
        媒体,
        解像度,
        スカイビュー条件,
        空中遠近条件,
        シェーダー,
    })?;
    Ok(大気のベイク済み画像の読み戻し {
        透過率: 読み戻し.透過率,
        多重散乱: 読み戻し.多重散乱,
        スカイビュー: 読み戻し.スカイビュー,
        空中遠近: 読み戻し.空中遠近,
        検証層の状況: 検証.状況,
        検証件数: 検証.件数,
    })
}
