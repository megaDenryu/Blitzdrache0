//! 縮小段の寸法の算術。原寸の幅と高さと段番号からその段の幅と高さを求める工程と、原寸が持てる縮小段の本数の上限を
//! 求める工程を持つ。段は前の段を切り捨てで半分にした寸法であり、1になった軸は1のまま残るため、段番号ぶんの右シフトと
//! 1への切り上げで求まる。
//!
//! 素材の段の並びの検査・画像の縮小段数の指定・コピー領域の寸法・blitの元と先の寸法が、すべてこの1つの算術を使う。
//! 別々に書くと、検査が通した段の並びをコピーが別の寸法で読む食い違いが起きる。
//!
//! 前提: 幅と高さはいずれも1以上である(零の寸法は`テクスチャ素材`の生成が拒む)。

/// 寸法を表す整数のビット数。u32の右シフトはこの数以上で定義されないため、段番号がここへ届いた時点で寸法は1に落ちている。
const 寸法のビット数: u32 = 32;

pub(crate) fn 縮小段の幅と高さを求める(原寸の幅: u32, 原寸の高さ: u32, 段番号: u32) -> (u32, u32) {
    (半分にする回数だけ縮める(原寸の幅, 段番号), 半分にする回数だけ縮める(原寸の高さ, 段番号))
}

/// 原寸から1x1まで並べたときの段の本数である。幅と高さの大きい方が1になるまで半分にした回数に1を足した数と等しい。
/// ビット長として整数演算だけで求め、浮動小数の丸め誤差を避ける。
pub(crate) fn 縮小段数の上限を求める(原寸の幅: u32, 原寸の高さ: u32) -> u32 {
    let 最大辺 = 原寸の幅.max(原寸の高さ).max(1);
    寸法のビット数 - 最大辺.leading_zeros()
}

fn 半分にする回数だけ縮める(原寸: u32, 段番号: u32) -> u32 {
    if 段番号 >= 寸法のビット数 {
        return 1;
    }
    (原寸 >> 段番号).max(1)
}
