//! 素材の段の並びの検査の反証。ブロック圧縮の段のバイト数がブロック数から求まること、
//! 縮小段をGPUで作る格納形式が段を持てないこと、段の本数と長さの逸脱を拒むことを見る。

#![allow(clippy::unwrap_used)]

use super::{テクスチャ格納形式, テクスチャ用途, テクスチャ素材, テクスチャ素材エラー};

/// 4の倍数でない寸法でも、段のバイト数は切り上げたブロック数から求まる。5x5は2x2ブロックで8バイトずつの32バイトである。
#[test]
fn ブロック圧縮の段は切り上げたブロック数のバイト数を要求する() {
    let 段0 = vec![0_u8; 32];
    let 段1 = vec![0_u8; 8];
    let 素材 = テクスチャ素材::生成する(5, 5, テクスチャ格納形式::BC1, vec![段0, 段1], テクスチャ用途::色).unwrap();
    assert_eq!(素材.縮小段数(), 2);
}

#[test]
fn ブロック圧縮の段が1バイト足りないと拒む() {
    let 段一覧 = vec![vec![0_u8; 7]];
    let 誤り = テクスチャ素材::生成する(4, 4, テクスチャ格納形式::BC1, 段一覧, テクスチャ用途::色).unwrap_err();
    assert_eq!(
        誤り,
        テクスチャ素材エラー::縮小段のバイト数不一致 {
            段番号: 0,
            期待長: 8,
            実長: 7
        }
    );
}

/// 非圧縮の縮小段は転送のblitが作るため、素材が段を持つとGPU上で二重になる。
#[test]
fn 縮小段をgpuで作る格納形式が段を2本持つと拒む() {
    let 誤り = テクスチャ素材::生成する(
        2,
        2,
        テクスチャ格納形式::RGBA8,
        vec![vec![0_u8; 16], vec![0_u8; 4]],
        テクスチャ用途::線形データ,
    )
    .unwrap_err();
    assert_eq!(誤り, テクスチャ素材エラー::GPUで作る格納形式が縮小段を持つ { 縮小段数: 2 });
}

/// 4x4は段0から1x1まで3本しか作れない。4本目は原寸から作れる段の外側である。
#[test]
fn 原寸から作れる本数を超える段を拒む() {
    let 段一覧 = vec![vec![0_u8; 8], vec![0_u8; 8], vec![0_u8; 8], vec![0_u8; 8]];
    let 誤り = テクスチャ素材::生成する(4, 4, テクスチャ格納形式::BC1, 段一覧, テクスチャ用途::色).unwrap_err();
    assert_eq!(誤り, テクスチャ素材エラー::縮小段数が上限を超える { 縮小段数: 4, 上限: 3 });
}

#[test]
fn 段を1本も持たない素材を拒む() {
    let 誤り = テクスチャ素材::生成する(1, 1, テクスチャ格納形式::BC1, Vec::new(), テクスチャ用途::色).unwrap_err();
    assert_eq!(誤り, テクスチャ素材エラー::縮小段が1本も無い);
}

#[test]
fn 零の寸法を拒む() {
    let 誤り = テクスチャ素材::rgba8の原寸から生成する(0, 4, Vec::new(), テクスチャ用途::色).unwrap_err();
    assert_eq!(誤り, テクスチャ素材エラー::寸法が零 { 幅: 0, 高さ: 4 });
}

#[test]
fn 非圧縮の原寸1枚は段を1本だけ持つ() {
    let 素材 = テクスチャ素材::rgba8の原寸から生成する(2, 2, vec![0_u8; 16], テクスチャ用途::色).unwrap();
    assert_eq!(素材.縮小段数(), 1);
    assert_eq!(素材.格納形式(), テクスチャ格納形式::RGBA8);
}
