//! 縮小段の並びを検査する工程。受け取るのは原寸の幅と高さとテクスチャ格納形式と段ごとのバイト列、返すのは受理か型付きエラーである。
//!
//! 見るのは5つである。寸法が零でないこと、段が1本以上あること、縮小段をGPUで作る格納形式が段を1本しか持たないこと、
//! 段の本数が原寸から作れる本数を超えないこと、段ごとのバイト数が格納形式の算術と一致することである。
//! 実行時形式の読み口も同型の検査を持つが、こちらはレンダラーの公開APIが直に受け取る値に対する検査であり、
//! ここを通った素材だけが画像の確保とコピーの寸法計算へ進む。

use super::error::テクスチャ素材エラー;
use super::level_extent::{縮小段の幅と高さを求める, 縮小段数の上限を求める};
use super::storage_format::テクスチャ格納形式;

pub(super) fn 縮小段の並びを検査する(
    幅: u32,
    高さ: u32,
    格納形式: テクスチャ格納形式,
    段ごとのバイト列: &[Vec<u8>],
) -> Result<(), テクスチャ素材エラー> {
    if 幅 == 0 || 高さ == 0 {
        return Err(テクスチャ素材エラー::寸法が零 { 幅, 高さ });
    }
    let 縮小段数 = u32::try_from(段ごとのバイト列.len()).map_err(|_| テクスチャ素材エラー::縮小段数が32ビットで表せない)?;
    if 縮小段数 == 0 {
        return Err(テクスチャ素材エラー::縮小段が1本も無い);
    }
    if !格納形式.縮小段をファイルが運ぶか() && 縮小段数 > 1 {
        return Err(テクスチャ素材エラー::GPUで作る格納形式が縮小段を持つ { 縮小段数 });
    }
    let 上限 = 縮小段数の上限を求める(幅, 高さ);
    if 縮小段数 > 上限 {
        return Err(テクスチャ素材エラー::縮小段数が上限を超える { 縮小段数, 上限 });
    }
    for (添字, バイト列) in 段ごとのバイト列.iter().enumerate() {
        let 段番号 = u32::try_from(添字).map_err(|_| テクスチャ素材エラー::縮小段数が32ビットで表せない)?;
        段のバイト数を照合する(幅, 高さ, 格納形式, 段番号, バイト列.len())?;
    }
    Ok(())
}

fn 段のバイト数を照合する(
    幅: u32,
    高さ: u32,
    格納形式: テクスチャ格納形式,
    段番号: u32,
    実長: usize,
) -> Result<(), テクスチャ素材エラー> {
    let (段の幅, 段の高さ) = 縮小段の幅と高さを求める(幅, 高さ, 段番号);
    let 期待長 = 格納形式.縮小段の格納バイト数を求める(段の幅, 段の高さ);
    // 期待長をusizeへ狭めてから比べる。狭められない期待長はこの機材のバイト列が到達できない長さであり、必ず不一致である。
    if usize::try_from(期待長).is_ok_and(|期待| 期待 == 実長) {
        return Ok(());
    }
    Err(テクスチャ素材エラー::縮小段のバイト数不一致 {
        段番号, 期待長, 実長
    })
}
