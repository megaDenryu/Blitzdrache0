//! `テクスチャ素材`の生成が拒む状態。GPUへ載せる手前で拒むため、拒む理由もこの1つの型に集める。

use thiserror::Error;

#[derive(Debug, Error, Clone, PartialEq, Eq)]
pub enum テクスチャ素材エラー {
    #[error("テクスチャの幅または高さが零である: 幅{幅} 高さ{高さ}")]
    寸法が零 { 幅: u32, 高さ: u32 }, // 画像は幅も高さも1画素以上である。零の寸法はVulkanの画像として作れない
    #[error("テクスチャが縮小段を1本も持たない")]
    縮小段が1本も無い,
    #[error("縮小段をGPUで作る格納形式のテクスチャが縮小段を{縮小段数}本持つ")]
    GPUで作る格納形式が縮小段を持つ { 縮小段数: u32 }, // 非圧縮の縮小段は転送のblitが原寸から作るため、素材が段を持つとGPU上で二重になる
    #[error("縮小段の本数{縮小段数}が原寸から作れる本数{上限}を超える")]
    縮小段数が上限を超える { 縮小段数: u32, 上限: u32 },
    #[error("縮小段の本数を32ビットで表せない")]
    縮小段数が32ビットで表せない,
    #[error("縮小段{段番号}の期待バイト数{期待長}と実長{実長}が一致しない")]
    縮小段のバイト数不一致 { 段番号: u32, 期待長: u128, 実長: usize },
}
