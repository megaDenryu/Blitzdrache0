//! テクスチャ格納形式: レンダラーが受け取るテクスチャの画素がどの符号化で並んでいるかの宣言と、
//! 縮小段1段の格納バイト数を求める算術。Vulkanの画像形式への写像は`vulkan/texture/format_support`が持つ。
//!
//! 注意: この算術は実行時形式のCPU正本(`crates/blitz_engine/src/asset/texture_storage/`)と同じ値を出さなければならない。
//! クレートの依存はblitz_engineからblitz_renderへの一方向であり、レンダラーから正本を呼べないため、同じ規則を両方が持つ。
//! 一致が破れると、焼いた段の長さがレンダラーの受け取りで拒まれる。

/// ブロック圧縮の族はどの形式も4x4の画素を1ブロックにする。
const ブロックの一辺の画素数: u32 = 4;

/// 非圧縮の1画素は赤・緑・青・不透明度の4バイトである。
const RGBA8の1画素のバイト数: u128 = 4;

/// BC1の1ブロックはRGB565の端点2つ(4バイト)と16画素の2ビットの索引(4バイト)である。
const BC1の1ブロックのバイト数: u128 = 8;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum テクスチャ格納形式 {
    RGBA8,
    BC1,
}

impl テクスチャ格納形式 {
    /// 縮小段1段の幅と高さから、その段がGPU上で占めるバイト数を求める。
    /// 128ビットで数えるのは、寸法の積が64ビットを超える入力でも算術を飽和させずに不一致として拒むためである。
    ///
    /// クレートの外へ公開するのは、この算術がCPU正本の写しであり、両者が同じ値を出すことを機械が検出できるようにするためである。
    /// 両クレートへ依存するのはコンポジションルート(blitz_app)だけであるため、突き合わせの検査をそこへ置くにはこの口が要る。
    /// 参照: `crates/blitz_app/src/app/scene_load/storage_byte_agreement_tests.rs`
    pub fn 縮小段の格納バイト数を求める(self, 段の幅: u32, 段の高さ: u32) -> u128 {
        match self {
            Self::RGBA8 => u128::from(段の幅) * u128::from(段の高さ) * RGBA8の1画素のバイト数,
            Self::BC1 => {
                let 横のブロック数 = 段の幅.div_ceil(ブロックの一辺の画素数);
                let 縦のブロック数 = 段の高さ.div_ceil(ブロックの一辺の画素数);
                u128::from(横のブロック数) * u128::from(縦のブロック数) * BC1の1ブロックのバイト数
            }
        }
    }

    /// 縮小段の連なりをファイルが運ぶか、原寸1枚だけを受け取ってGPUが残りを作るか。
    /// ブロック圧縮の画像を書き込み先とするblitは成立しないため、圧縮した段はファイルが運ぶしかない
    /// (参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`「判断d」)。
    pub(crate) fn 縮小段をファイルが運ぶか(self) -> bool {
        match self {
            Self::RGBA8 => false,
            Self::BC1 => true,
        }
    }
}
