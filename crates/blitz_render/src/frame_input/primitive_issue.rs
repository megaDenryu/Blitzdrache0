//! プリミティブ描画発行: 1つのプリミティブを描くために描画発行が要る値。どの詳細段のどのインデックス区間を、どの材質スロットで塗るかである。
//!
//! インデックス区間を値で持つのは、描画発行の時点で元のメッシュデータが既に無いためである(参照: `_doc/設計/マルチマテリアルと材質境界.md`「可視ID列の契約」)。
//! 生成でGPUが受け取る幅へ狭めるのは、区間がCPU側では配列の添字と長さであり、描画発行ではu32だからである。頂点基準を符号付きへ写すのも同じ境界の仕事であり、
//! 収まらない値を無言で丸めずに型付きエラーで拒む。
//! インスタンス数と先頭インスタンスを持たないのは、それらが可視選別の結果である段別描画範囲から来る値であり、同じ描画対象の全プリミティブで共有されるためである。

use crate::error::レンダラーエラー;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct プリミティブ描画発行 {
    詳細段番号: usize,
    インデックス開始: u32,
    インデックス数: u32,
    頂点基準: i32,
    材質スロット番号: u32,
}

impl プリミティブ描画発行 {
    pub fn 生成する(
        詳細段番号: usize,
        インデックス開始: usize,
        インデックス数: usize,
        頂点基準: u32,
        材質スロット番号: u32,
    ) -> Result<Self, レンダラーエラー> {
        let 頂点基準 = i32::try_from(頂点基準).map_err(|_| レンダラーエラー::プリミティブ区間過大(u64::from(頂点基準)))?;
        Ok(Self {
            詳細段番号,
            インデックス開始: u32へ狭める(インデックス開始)?,
            インデックス数: u32へ狭める(インデックス数)?,
            頂点基準,
            材質スロット番号,
        })
    }

    pub(crate) fn 詳細段番号(self) -> usize {
        self.詳細段番号
    }

    pub(crate) fn インデックス開始(self) -> u32 {
        self.インデックス開始
    }

    pub(crate) fn インデックス数(self) -> u32 {
        self.インデックス数
    }

    pub(crate) fn 頂点基準(self) -> i32 {
        self.頂点基準
    }

    pub(crate) fn 材質スロット番号(self) -> u32 {
        self.材質スロット番号
    }
}

/// u64へ写せない大きさのusizeは現行の対応環境に存在しないが、写せないときも値を落とさずに飽和させて報告する。
fn u32へ狭める(値: usize) -> Result<u32, レンダラーエラー> {
    u32::try_from(値).map_err(|_| レンダラーエラー::プリミティブ区間過大(u64::try_from(値).unwrap_or(u64::MAX)))
}
