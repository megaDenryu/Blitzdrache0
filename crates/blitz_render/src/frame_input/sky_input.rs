//! 空パスの1フレーム入力。Hosek-Wilkie解析近似の係数はエンジン層が焼き、ここはその結果をGPU境界まで運ぶ。
//! 不変条件(有限性・非負・昼係数の値域・太陽方向の単位長・角半径の値域)はすべて`生成する`が確かめる。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「空の方式」

use blitz_math::ラジアン;
use thiserror::Error;

/// 解析近似の方向係数の個数(A〜I)。GPU側の`shaders/sky.slang`の宣言と一致させる。
pub const 空の方向係数の個数: usize = 9;

#[derive(Debug, Clone, Copy)]
pub struct 空入力 {
    pub(crate) 方向係数: [[f32; 3]; 空の方向係数の個数],
    pub(crate) 放射輝度スケール: [f32; 3],
    pub(crate) 夜空放射輝度: [f32; 3],
    pub(crate) 昼係数: f32,
    /// 地表から太陽へ向かう単位ベクトル。X が東、Y が天頂、Z が南である。
    pub(crate) 太陽方向: [f32; 3],
    pub(crate) 太陽円盤放射輝度: [f32; 3],
    pub(crate) 太陽円盤角半径: ラジアン,
}

#[derive(Debug, Clone, Copy, Error, PartialEq, Eq)]
pub enum 空入力エラー {
    #[error("{0}が有限でない")]
    非有限(&'static str),
    #[error("{0}が負である")]
    負の放射輝度(&'static str),
    #[error("昼係数が0以上1以下でない")]
    昼係数が値域外,
    #[error("太陽方向がゼロ長である")]
    太陽方向がゼロ長,
    #[error("太陽円盤角半径が0より大きく直角未満でない")]
    太陽円盤角半径が値域外,
}

impl 空入力 {
    pub fn 生成する(
        方向係数: [[f32; 3]; 空の方向係数の個数],
        放射輝度スケール: [f32; 3],
        夜空放射輝度: [f32; 3],
        昼係数: f32,
        太陽方向: [f32; 3],
        太陽円盤放射輝度: [f32; 3],
        太陽円盤角半径: ラジアン,
    ) -> Result<Self, 空入力エラー> {
        if 方向係数.iter().flatten().any(|値| !値.is_finite()) {
            return Err(空入力エラー::非有限("方向係数"));
        }
        非負を求める(&放射輝度スケール, "放射輝度スケール")?;
        非負を求める(&夜空放射輝度, "夜空放射輝度")?;
        非負を求める(&太陽円盤放射輝度, "太陽円盤放射輝度")?;
        if !昼係数.is_finite() || !(0.0..=1.0).contains(&昼係数) {
            return Err(空入力エラー::昼係数が値域外);
        }
        有限を求める(&太陽方向, "太陽方向")?;
        let 半径 = 太陽円盤角半径.値();
        if !半径.is_finite() || 半径 <= 0.0 || 半径 >= std::f32::consts::FRAC_PI_2 {
            return Err(空入力エラー::太陽円盤角半径が値域外);
        }
        Ok(Self {
            方向係数,
            放射輝度スケール,
            夜空放射輝度,
            昼係数,
            太陽方向: 単位化する(太陽方向)?,
            太陽円盤放射輝度,
            太陽円盤角半径,
        })
    }
}

fn 有限を求める(値一覧: &[f32], 名前: &'static str) -> Result<(), 空入力エラー> {
    if 値一覧.iter().any(|値| !値.is_finite()) {
        return Err(空入力エラー::非有限(名前));
    }
    Ok(())
}

fn 非負を求める(値一覧: &[f32; 3], 名前: &'static str) -> Result<(), 空入力エラー> {
    有限を求める(値一覧, 名前)?;
    if 値一覧.iter().any(|値| *値 < 0.0) {
        return Err(空入力エラー::負の放射輝度(名前));
    }
    Ok(())
}

fn 単位化する(方向: [f32; 3]) -> Result<[f32; 3], 空入力エラー> {
    let 長さ二乗: f32 = 方向.iter().map(|値| 値 * 値).sum();
    if !長さ二乗.is_finite() || 長さ二乗 <= f32::EPSILON {
        return Err(空入力エラー::太陽方向がゼロ長);
    }
    let 逆長さ = 長さ二乗.sqrt().recip();
    Ok(方向.map(|値| 値 * 逆長さ))
}
