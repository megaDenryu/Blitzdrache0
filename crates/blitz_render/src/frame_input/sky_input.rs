//! 空パスの1フレーム入力。時刻から導いた太陽の向きと、時刻に依らない空描画方針の値をGPU境界まで運ぶ。
//! 空の放射輝度そのものはプリコンピュート大気のベイク済み画像を参照して求めるため、この入力は空の放射輝度を運ばない。
//!
//! 検証前の値の組を`空入力の材料`、値域を確かめ太陽方向を単位化した後の値を`空入力`とする。
//! 不変条件(有限性・非負・太陽方向の単位長・角半径と観測高度と放射照度の値域)の検査は`validation`が持つ。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「空の方式」

mod validation;

use blitz_math::{メートル, ラジアン};
use thiserror::Error;

/// 空パスへ渡す値の組。検証前の生の値であり、`空入力::生成する`を通ってはじめて空パスへ渡せる。
#[derive(Debug, Clone, Copy)]
pub struct 空入力の材料 {
    /// 太陽が地平線より下でも常時加算する夜間の背景放射輝度。
    pub 夜空放射輝度: [f32; 3],
    /// 地表から太陽へ向かうベクトル。X が東、Y が天頂、Z が南である。単位化は`空入力::生成する`が行う。
    pub 太陽方向: [f32; 3],
    pub 太陽円盤放射輝度: [f32; 3],
    pub 太陽円盤角半径: ラジアン,
    /// スカイビューのベイク済み画像を焼いた観測点の地表からの高さ。大気のベイク済み画像方式が観測半径を組むのに使う。
    pub 観測高度: メートル,
    /// 太陽の放射照度の尺度。スカイビューのベイク済み画像は放射照度1で焼くため、描画側がこの値を掛ける。
    pub 太陽放射照度: f32,
}

/// 値域を確かめ、太陽方向を単位化した空パスの入力。
#[derive(Debug, Clone, Copy)]
pub struct 空入力 {
    材料: 空入力の材料,
}

#[derive(Debug, Clone, Copy, Error, PartialEq, Eq)]
pub enum 空入力エラー {
    #[error("{0}が有限でない")]
    非有限(&'static str),
    #[error("{0}が負である")]
    負の放射輝度(&'static str),
    #[error("太陽方向がゼロ長である")]
    太陽方向がゼロ長,
    #[error("太陽円盤角半径が0より大きく直角未満でない")]
    太陽円盤角半径が値域外,
    #[error("観測高度が有限かつ0以上でない")]
    観測高度が値域外,
    #[error("太陽放射照度が有限かつ0より大きくない")]
    太陽放射照度が値域外,
}

impl 空入力 {
    pub fn 生成する(材料: 空入力の材料) -> Result<Self, 空入力エラー> {
        validation::確かめる(&材料)?;
        Ok(Self {
            材料: 空入力の材料 {
                太陽方向: validation::単位化する(材料.太陽方向)?,
                ..材料
            },
        })
    }

    /// 検証済みの値の組。空パス定数を組み立てる側が読む。
    pub(crate) fn 材料(&self) -> &空入力の材料 {
        &self.材料
    }
}
