//! プリミティブ発行受け皿: 全描画対象ぶんのプリミティブ描画発行を1本の列へ連ね、描画対象ごとの区間を索引として持つ器。
//! 呼び出し元が毎フレーム詰め直して使い回す。器がレンダラー側にあるのは、区間の切り方と引き当ての規律が描画発行の都合で決まるためであり、
//! 呼び出し元は束IDと描画対象添字を添えて積むことだけを知ればよい。
//!
//! 1本の列へ連ねるのは、常駐する描画対象の数だけVecを持つと束の出入りのたびに確保が起きるためである。
//! 空にするのは長さを戻すだけであり、確保済みの容量は次のフレームへ持ち越す。
//! 引き当てが索引の線形走査なのは、索引の件数が常駐する描画対象の数であり、可視個体選択の一覧と同じ桁に収まるためである。
//! 発行列そのものを走査しないのは、そちらの件数が描画対象数にプリミティブ数を掛けた大きさになるからである。

use super::primitive_issue::プリミティブ描画発行;
use super::primitive_issue_section::プリミティブ発行区間;
use crate::draw_bundle_id::描画束ID;

#[derive(Debug, Default)]
pub struct プリミティブ発行受け皿 {
    索引: Vec<プリミティブ発行区間>,
    発行列: Vec<プリミティブ描画発行>,
}

impl プリミティブ発行受け皿 {
    pub fn 生成する() -> Self {
        Self::default()
    }

    pub fn 空にする(&mut self) {
        self.索引.clear();
        self.発行列.clear();
    }

    /// 直前に積んだものと同じ描画対象なら区間を伸ばし、変わっていれば新しい区間を開く。
    /// 注意: 1つの描画対象のプリミティブは続けて積む。間に別の描画対象を挟むと、同じ対象の区間が2つに割れて後の区間だけが引かれる。
    pub fn 積む(&mut self, 束id: 描画束ID, 描画対象添字: usize, 発行: プリミティブ描画発行) {
        self.発行列.push(発行);
        match self.索引.last_mut() {
            Some(区間) if 区間.同じ描画対象か(束id, 描画対象添字) => 区間.件数を1つ足す(),
            _ => self.索引.push(プリミティブ発行区間::生成する(束id, 描画対象添字, self.発行列.len() - 1)),
        }
    }

    /// その描画対象が描くプリミティブの並び。索引に無い描画対象と、索引が発行列の外を指す区間には`None`を返す。
    /// 空の並びを返さないのは、プリミティブを1つも持たない描画対象が契約上あり得ず、呼び出し元がそれを型付きエラーにするためである。
    pub(crate) fn 引く(&self, 束id: 描画束ID, 描画対象添字: usize) -> Option<&[プリミティブ描画発行]> {
        let 区間 = self.索引.iter().find(|区間| 区間.同じ描画対象か(束id, 描画対象添字))?;
        let 並び = self.発行列.get(区間.開始()..区間.終端()?)?;
        if 並び.is_empty() { None } else { Some(並び) }
    }
}
