//! 布シミュレーションがその描画で進める固定刻みの本数。担当するのは「本数を1つ持ち、上限の中に収まっていることを
//! 保証する」ことだけであり、刻み1本の長さも、刻みの中で積む工程も知らない。
//!
//! 上限を型が持つのは、布の工程を刻み数ぶん繰り返す形が1フレームのパス数を刻み数に比例して増やすためである。
//! パス別GPU計測のクエリプールの容量はこの上限から決まる。上限を越えた本数はここで型付きの失敗として拒み、
//! グラフの奥でクエリの添字がプールの外を指してpanicする形にしない。
//! 参照: `_doc/設計/時間の規律.md`「判断3」「判断5」。

use crate::error::布エラー;

/// 布が1描画で進められる固定刻みの本数の上限。
/// 時間進行方針の一描画で進める刻み数の上限(初期値4)を実測で動かす余地を持たせた値である。
const 上限の本数: u32 = 8;

/// その描画で布シミュレーションを何本の固定刻みぶん進めるか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct 布の進める刻み数(u32);

impl 布の進める刻み数 {
    /// 上限を越えた本数は型付きの失敗にする。既定値で丸めると、進んだゲームの時間と布の進みが黙って食い違う。
    pub fn 生成する(本数: u32) -> Result<Self, 布エラー> {
        if 本数 > 上限の本数 {
            return Err(布エラー::刻み数超過 {
                本数, 上限: 上限の本数
            });
        }
        Ok(Self(本数))
    }

    /// 刻みを1本も進めない描画。蓄積が基本刻みに届かなかった描画がこの値を渡す。
    pub fn 一つも進めない() -> Self {
        Self(0)
    }

    pub(crate) fn 本数(self) -> u32 {
        self.0
    }

    /// 1フレームのパス数の上限を組み立てる側が読む。
    pub(crate) const fn 上限の本数() -> u32 {
        上限の本数
    }
}
