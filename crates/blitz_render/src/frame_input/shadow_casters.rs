//! そのフレームのシャドウパスへ何を積むかの指定。担当するのは「距離区分のパスが描画入力を持つかどうか」だけである。
//!
//! 全キャスターを外した対照はシャドウパスそのものは積む。深度配列の消去と保存の費用を残したまま描く物だけを消すことで、
//! 通常との差がキャスターの描画費用そのものになり、残りが添付処理の切片になる。パスごと積まない形にすると
//! 消去と保存も一緒に消えて切片が測れないうえ、前フレームの深度が影として残る
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」)。
//!
//! 注意: 群の個体だけを影の候補から外す指定とは別物である。あちらは可視個体の選別の枝であり、
//! 個体を持たない描画対象(地形)と布はそのまま影を落とし続ける。

use crate::visible_instance_selection::可視パス;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 影のキャスター指定 {
    /// 本番。可視判定が通した対象をすべて距離区分のパスへ積む。
    通常に描く,
    /// 計測専用の対照。地形も個体も布も距離区分のパスへ1件も積まない。
    全て外す,
}

impl 影のキャスター指定 {
    /// そのフレームに描画入力を積むパス。全て外した対照ではシーンパスだけが残る。
    /// 数え上げもこの並びで回すため、外したパスの発行数・可視数・個体数・投入インデックス数はすべて0になり、
    /// 「数えた数」と「積んだ発行」が食い違わない。
    pub(crate) fn 積むパス一覧(self) -> impl Iterator<Item = 可視パス> {
        可視パス::全パス().filter(move |パス| self.このパスへ積むか(*パス))
    }

    fn このパスへ積むか(self, パス: 可視パス) -> bool {
        matches!(パス, 可視パス::シーン) || self.影へ積むか()
    }

    /// 距離区分のパスへ描画入力を積むか。地形・個体・布のどれについても同じ答えになる。
    pub(crate) fn 影へ積むか(self) -> bool {
        match self {
            Self::通常に描く => true,
            Self::全て外す => false,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::cascade::距離区分数;

    #[test]
    fn 通常は全パスへ積む() {
        assert_eq!(影のキャスター指定::通常に描く.積むパス一覧().count(), 1 + 距離区分数);
    }

    #[test]
    fn 全て外すとシーンパスだけが残る() {
        let 一覧: Vec<可視パス> = 影のキャスター指定::全て外す.積むパス一覧().collect();
        assert_eq!(一覧, vec![可視パス::シーン]);
    }
}
