//! そのフレームに動く個体を置く大域の位置と向きの指定。担当するのは「どの束のどの描画対象のどの個体を、世界のどこへ、
//! 読込時の向きからどれだけ回して置くか」を1件ぶん運ぶことだけであり、寸法は持たない。
//!
//! 寸法を持たないのは、読込時に書いた個体変換のうち平行移動の成分と天頂軸まわりの向きだけを毎フレーム差し替える形にしたためである。
//! 動く個体が大きさを変える要求が立った時点で、この型へ倍率を足す。
//!
//! 位置をf32でなく大域ワールド位置で受けるのは、ゲームの状態が持つ位置がf64の大域位置であり、
//! 描画の基準原点を引いてf32へ狭める境界をレンダラーの側に1箇所だけ置くためである。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断5: 動くオブジェクトはゲーム状態が正本であり、描画へは毎フレーム供給する」

use blitz_math::大域ワールド位置;

use crate::draw_bundle_id::描画束ID;
use crate::frame_input::読込時の向きから天頂軸まわりに回す角;

/// 動く個体1体ぶんの、そのフレームの大域の位置と向きの指定。`描画対象添字`は読込時の`動く個体の宣言`と同じ意味の
/// 添字である。`読込時の向きから回す角`を、世界のどちらを向くかでなく差で受ける理由は
/// `読込時の向きから天頂軸まわりに回す角`にある。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 動く個体の大域の位置と向きの指定 {
    pub 束id: 描画束ID,
    pub 描画対象添字: usize, // 束の中での描画対象の並び順
    pub 個体添字: u32,
    pub 大域位置: 大域ワールド位置,
    pub 読込時の向きから回す角: 読込時の向きから天頂軸まわりに回す角, // 読込時の姿勢から回す角
}
