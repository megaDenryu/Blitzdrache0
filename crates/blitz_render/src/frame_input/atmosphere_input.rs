//! 大気LUTの1フレーム入力。焼く大気そのものと、そのフレームで焼き直すかどうかの指示を1つに束ねる。
//!
//! 焼き直すかどうかを上位層が決めるのは、判定に使う鍵が方針の全パラメータを並べた完全比較キーであり、
//! それを持つのが方針を保持する層だからである。可変なdirty通知でなく値の比較で決めるため、
//! 通知の付け忘れという欠陥の種類そのものが生じない。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「更新の決定性」

use crate::atmosphere::大気散乱媒体;

/// そのフレームで大気LUTを焼き直すかどうか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 大気LUT生成指示 {
    /// 大気が前フレームから変わった、またはまだ1度も焼いていない。生成パスを積む。
    焼き直す,
    /// 大気が前フレームと同じである。生成パスを1本も積まず、前に焼いた中身をそのまま使う。
    前の結果を使う,
}

/// 空を持つ世界のフレームが毎フレーム渡す大気の入力。
#[derive(Debug, Clone, Copy)]
pub struct 大気LUT入力 {
    媒体: 大気散乱媒体,
    生成指示: 大気LUT生成指示,
}

impl 大気LUT入力 {
    pub fn 生成する(媒体: 大気散乱媒体, 生成指示: 大気LUT生成指示) -> Self {
        Self { 媒体, 生成指示 }
    }

    pub(crate) fn 媒体(&self) -> &大気散乱媒体 {
        &self.媒体
    }

    pub(crate) fn 焼き直すか(&self) -> bool {
        matches!(self.生成指示, 大気LUT生成指示::焼き直す)
    }
}
