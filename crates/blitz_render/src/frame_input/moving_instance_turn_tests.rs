//! 動く個体の向きを寄せる演算の試験。担当するのは、係数0でこの角が1ビットも変わらないことと、
//! 一周をまたぐ2つの向きが短い側の弧を回ることの2つを固定することである。
//!
//! 前者を落とすと、フレーム数の決まった実行の絵が補間の導入だけで変わる。後者を落とすと、北を挟んで向きを変えた個体が
//! 1刻みのあいだにほぼ一周ぶん回る。参照: `_doc/設計/時間の規律.md`「判断6」。

use blitz_math::ラジアン;

use super::読込時の向きから天頂軸まわりに回す角;

fn 角(度: f32) -> 読込時の向きから天頂軸まわりに回す角 {
    読込時の向きから天頂軸まわりに回す角::生成する(ラジアン::度から(度))
}

fn 度で読む(対象: 読込時の向きから天頂軸まわりに回す角) -> f32 {
    対象.ラジアンで表した角().値().to_degrees()
}

#[test]
fn 係数0ではこの角そのものが返る() {
    let 現在 = 角(170.0);
    assert_eq!(現在.最短の弧で相手の側へ係数ぶん寄せる(角(-170.0), 0.0), 現在);
}

#[test]
fn 係数1では相手の角と同じ向きへ到達する() {
    let 寄せた角 = 角(0.0).最短の弧で相手の側へ係数ぶん寄せる(角(90.0), 1.0);
    assert!((度で読む(寄せた角) - 90.0).abs() < 1.0e-3);
}

/// 反証: 差を畳まずに掛けると、170度から-170度への20度の変化が逆向きの340度の回転になる。
#[test]
fn 一周をまたぐ2つの向きは短い側の弧を回る() {
    let 寄せた角 = 角(170.0).最短の弧で相手の側へ係数ぶん寄せる(角(-170.0), 0.5);
    assert!((度で読む(寄せた角) - 180.0).abs() < 1.0e-3);
}

/// 半周ちょうどの差はどちらの弧も同じ長さである。正の側へ決め打つのは、同じ入力の描画が実行ごとに逆へ回らないためである。
#[test]
fn 半周ちょうどの差は正の側の弧を回る() {
    let 寄せた角 = 角(0.0).最短の弧で相手の側へ係数ぶん寄せる(角(180.0), 0.5);
    assert!((度で読む(寄せた角) - 90.0).abs() < 1.0e-3);
}
