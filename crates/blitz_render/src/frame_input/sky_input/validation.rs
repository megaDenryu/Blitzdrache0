//! 空入力の材料の値域検査と、太陽方向の単位化。受け取るのは材料、返すのは破れた不変条件を示すエラーである。
//!
//! 検査を材料と同じ場所に置かないのは、材料が「何を運ぶか」の宣言、ここが「どこまでを正しい値とみなすか」の
//! 判断であり、値の並びを読むときと判断を直すときで開くファイルが違うためである。

use super::{空入力の材料, 空入力エラー};

pub(super) fn 確かめる(材料: &空入力の材料) -> Result<(), 空入力エラー> {
    非負を求める(&材料.夜空放射輝度, "夜空放射輝度")?;
    非負を求める(&材料.太陽円盤放射輝度, "太陽円盤放射輝度")?;
    有限を求める(&材料.太陽方向, "太陽方向")?;
    let 半径 = 材料.太陽円盤角半径.値();
    if !半径.is_finite() || 半径 <= 0.0 || 半径 >= std::f32::consts::FRAC_PI_2 {
        return Err(空入力エラー::太陽円盤角半径が値域外);
    }
    if !材料.観測高度.値().is_finite() || 材料.観測高度.値() < 0.0 {
        return Err(空入力エラー::観測高度が値域外);
    }
    if !材料.太陽放射照度.is_finite() || 材料.太陽放射照度 <= 0.0 {
        return Err(空入力エラー::太陽放射照度が値域外);
    }
    Ok(())
}

/// 太陽方向を単位ベクトルへ直す。長さ0の向きは太陽の位置を表せないため型付きエラーにする。
pub(super) fn 単位化する(方向: [f32; 3]) -> Result<[f32; 3], 空入力エラー> {
    let 長さ二乗: f32 = 方向.iter().map(|値| 値 * 値).sum();
    if !長さ二乗.is_finite() || 長さ二乗 <= f32::EPSILON {
        return Err(空入力エラー::太陽方向がゼロ長);
    }
    let 逆長さ = 長さ二乗.sqrt().recip();
    Ok(方向.map(|値| 値 * 逆長さ))
}

fn 有限を求める(値一覧: &[f32], 名前: &'static str) -> Result<(), 空入力エラー> {
    if 値一覧.iter().any(|値| !値.is_finite()) {
        return Err(空入力エラー::非有限(名前));
    }
    Ok(())
}

fn 非負を求める(値一覧: &[f32; 3], 名前: &'static str) -> Result<(), 空入力エラー> {
    有限を求める(値一覧, 名前)?;
    if 値一覧.iter().any(|値| *値 < 0.0) {
        return Err(空入力エラー::負の放射輝度(名前));
    }
    Ok(())
}
