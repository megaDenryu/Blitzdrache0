//! 動く個体を読込時の姿勢からどれだけ回すかを表す角。担当するのは角1つと、回す軸と正の向きの規約だけであり、
//! 回した先が世界のどちらを向くかは知らない。
//!
//! 世界での向きそのものでなく読込時の姿勢からの差で受けるのは、レンダラーが個体の姿勢の正本を持たないためである。
//! 読込時に焼かれた変換の向きと寸法をそのまま使い、その上へこの回転を掛ける。世界のどちらを向くかを決めるのはゲームの側であり、
//! そのモデルがどちらを向いて焼かれているかを知る配線が、世界での向きをこの差へ写す。
//!
//! 回す軸を天頂軸だけに限るのは、動く個体が地面の上を歩いて向きを変えるためである。傾きや横倒しの要求が立った時点で、
//! 3軸の姿勢を表す型へ差し替える。

use blitz_math::ラジアン;

/// 読込時の向きから天頂軸(ワールドのY軸)まわりに回す角。0は読込時の向きそのままである。
/// 正の回転は北(Zの負の向き)を西(Xの負の向き)へ回す向きである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 読込時の向きから天頂軸まわりに回す角(ラジアン);

impl 読込時の向きから天頂軸まわりに回す角 {
    pub fn 生成する(角: ラジアン) -> Self {
        Self(角)
    }

    /// 相手の角の側へ、最短の弧で係数ぶん寄せた角。0でこの角そのもの、1で相手の角になる。
    /// 描画補間が現在の確定値から前の確定値の側へ戻すのに使う(参照: `_doc/設計/時間の規律.md`「判断6」)。
    ///
    /// 差を一周の中で正負の半周へ畳んでから掛けるのは、北を挟んで向きを変えた個体が長い側の弧を
    /// ほぼ一周ぶん回るのを避けるためである。
    ///
    /// 注意: 係数0でこの角を1ビットも変えずに返すことが、フレーム数の決まった実行の絵を補間の導入前と
    /// 一致させる根拠である。2つの角へ重みを掛けて足す形も、畳んだ差へ0を掛けた値を足す形もこれを満たさない。
    /// 後者が満たさないのは負のゼロがあるためである。この角が-0.0で相手が正のとき、畳んだ差は正、それへ0を
    /// 掛けた値は+0.0、-0.0に+0.0を足した値は+0.0になり、符号のビットが落ちる。係数0をそのまま返す枝で塞ぐ。
    pub fn 最短の弧で相手の側へ係数ぶん寄せる(self, 相手: Self, 係数: f32) -> Self {
        if 係数 == 0.0 {
            return self;
        }
        Self(self.0 + (相手.0 - self.0).一周の中で最短の弧へ畳む() * 係数)
    }

    /// GPU境界向けの取り出し。個体レコードの行列を組む工程だけが読む。
    pub(crate) fn ラジアンで表した角(self) -> ラジアン {
        self.0
    }
}
