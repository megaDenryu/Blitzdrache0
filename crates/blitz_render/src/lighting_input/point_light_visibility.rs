//! 1件の点光源が影を落とすかどうかの判別。
//!
//! 影を落とさない状態を強度0や影資源添字の番兵で代用しないのは、光の強さと影の有無が別の概念だからである
//! (方向光の`影の落ち方`と同じ理由である)。
//!
//! 既定値を持たないのは、影を持てる灯の件数に上限があるためである。既定を「影なし」に置くと、宣言し忘れた灯が
//! 黙って壁を抜けて照り、その絵がそう宣言した結果なのか宣言し忘れた結果なのかを入力から読めなくなる。
//! 既定を「立方体影」に置くと、影の要らない灯を上限より多く並べただけで起動しなくなる
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断k」)。

/// 点光源の可視性。`立方体影`の灯だけが立方体配列の1つを占め、影資源添字を受け取る。
/// 添字そのものはこの型に現れない。割り当てるのは局所光源列を完成させる口だけである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 点光源の可視性 {
    影なし,
    立方体影,
}

impl 点光源の可視性 {
    pub(crate) fn 影を落とすか(self) -> bool {
        matches!(self, Self::立方体影)
    }
}
