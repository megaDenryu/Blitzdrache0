//! 方向光シャドウの正射影を毎フレーム組み立てるための再構築パラメータ。
//! 焼いた行列で持つと、カメラ大域原点を引いた相対フレームでは作り直せないため、注視点の大域位置と正射影の寸法で持つ。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「カメラ相対描画の契約」

use blitz_math::{ビュー, メートル, ワールド, 位置, 光源クリップ, 変換, 大域ワールド位置, 座標変換エラー};

use super::{ライティング入力エラー, 方向光入力};

/// 正射影の見える範囲。半幅2つと前後クリップ2つは常に一組で意味を持つため、1つの値として渡す。
#[derive(Debug, Clone, Copy)]
pub struct 影正射影範囲 {
    横半幅: メートル,
    縦半幅: メートル,
    近クリップ: メートル,
    遠クリップ: メートル,
}

impl 影正射影範囲 {
    pub fn 生成する(
        横半幅: メートル,
        縦半幅: メートル,
        近クリップ: メートル,
        遠クリップ: メートル,
    ) -> Result<Self, ライティング入力エラー> {
        let 正であるべき値 = [横半幅, 縦半幅, 近クリップ, 遠クリップ];
        if 正であるべき値.iter().any(|値| !値.値().is_finite() || 値.値() <= 0.0) {
            return Err(ライティング入力エラー::影正射影範囲不正);
        }
        if 近クリップ >= 遠クリップ {
            return Err(ライティング入力エラー::影正射影範囲不正);
        }
        Ok(Self {
            横半幅,
            縦半幅,
            近クリップ,
            遠クリップ,
        })
    }
}

#[derive(Debug, Clone, Copy)]
pub struct 影入力 {
    注視点: 大域ワールド位置,
    光源距離: メートル,
    範囲: 影正射影範囲,
}

impl 影入力 {
    /// `注視点`は正射影の中心が向く大域位置、`光源距離`はそこから方向光の逆向きへ光源を離す距離である。
    pub fn 生成する(
        注視点: 大域ワールド位置, 光源距離: メートル, 範囲: 影正射影範囲
    ) -> Result<Self, ライティング入力エラー> {
        let 成分一覧 = [注視点.x().値(), 注視点.y().値(), 注視点.z().値()];
        if 成分一覧.iter().any(|成分| !成分.is_finite()) {
            return Err(ライティング入力エラー::影注視点不正);
        }
        if !光源距離.値().is_finite() || 光源距離.値() <= 0.0 {
            return Err(ライティング入力エラー::影光源距離不正);
        }
        Ok(Self {
            注視点, 光源距離, 範囲
        })
    }

    pub fn 注視点(self) -> 大域ワールド位置 {
        self.注視点
    }

    /// 与えた原点を引いた相対フレームでライトビュー射影を組み立てる。フレームUBOの書き込みが毎フレーム呼ぶ。
    /// 注意: 方向光の向きは平行移動に依存しないため原点を引かない。対象側と同じ原点を渡すことが呼び出し元の責務である。
    pub(crate) fn ライトビュー射影を組み立てる(
        self,
        方向光: 方向光入力,
        相対フレーム原点: 大域ワールド位置,
    ) -> Result<変換<ワールド, 光源クリップ>, 座標変換エラー> {
        let 相対注視点 = self.注視点.カメラ相対へ変換する(相対フレーム原点)?;
        let 注視点: 位置<ワールド> = 位置::生成する(相対注視点.x(), 相対注視点.y(), 相対注視点.z());
        let 光源へのずれ = 方向光.逆方向へ離れた位置(self.光源距離);
        let 光源位置: 位置<ワールド> = 位置::生成する(
            注視点.x() + 光源へのずれ.x(),
            注視点.y() + 光源へのずれ.y(),
            注視点.z() + 光源へのずれ.z(),
        );
        let ビュー変換: 変換<ワールド, ビュー> = 変換::注視(光源位置, 注視点);
        let 投影: 変換<ビュー, 光源クリップ> = 変換::正射影(self.範囲.横半幅, self.範囲.縦半幅, self.範囲.近クリップ, self.範囲.遠クリップ);
        Ok(ビュー変換.合成する(投影))
    }
}
