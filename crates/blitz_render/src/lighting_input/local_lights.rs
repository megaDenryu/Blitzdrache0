/// 1フレームが持てる局所光の件数の上限。GPUの局所光レコード列の要素数がこの値であり
/// (`crates/blitz_render/src/vulkan/lighting_query/capacity.rs`が同じ値をここから読む)、
/// 超える宣言は梱包まで進ませず生成の時点で型付きの失敗にする。
///
/// 64件にした根拠は3つある。夜の街灯を並べた検収の世界と屋内1部屋がこの桁で収まること、
/// 1件64バイトのレコードがフレームスロットあたり4キロバイトに収まり進行中フレーム数を掛けても常駐量が問題にならないこと、
/// 仮置きの分割数(横16・縦8・奥行き24=3072セル)でセルごとに全光を指しても添字の総数が実装可能な桁に留まることである。
const 局所光源の上限件数: usize = 64;

/// 1件の宣言された局所光と、その灯へ割り当てた影の資源。
#[derive(Debug, Clone, Copy)]
struct 宣言された局所光 {
    点光源: 点光源入力,
    影の割り当て: Option<影を落とす灯の割り当て>,
}

/// 世界が宣言した局所光の並び。
///
/// 注意: 枠の先頭から件数ぶんが`Some`であり、その後ろは必ず`None`である。この並びを作れるのは`生成する`だけであり、
/// 途中に穴の空いた列は外から作れない。影資源添字も同じ`生成する`だけが決める。
#[derive(Debug, Clone, Copy)]
pub struct 局所光源列 {
    枠: [Option<宣言された局所光>; 局所光源の上限件数],
}

impl 局所光源列 {
    pub const 上限件数: usize = 局所光源の上限件数;

    pub fn 生成する(点光源一覧: &[点光源入力]) -> Result<Self, ライティング入力エラー> {
        if 点光源一覧.len() > Self::上限件数 {
            return Err(ライティング入力エラー::局所光源列の件数が上限を超えた {
                件数: 点光源一覧.len(),
                上限: Self::上限件数,
            });
        }
        let 割り当て一覧 = 宣言の順に影の資源を割り当てる(点光源一覧)?;
        let mut 枠 = [None; 局所光源の上限件数];
        for (添字, (点光源, 割り当て)) in 点光源一覧.iter().zip(割り当て一覧).enumerate() {
            枠[添字] = Some(宣言された局所光 {
                点光源: *点光源,
                影の割り当て: 割り当て,
            });
        }
        Ok(Self { 枠 })
    }

    pub fn 件数(&self) -> usize {
        self.枠.iter().flatten().count()
    }

    pub fn 点光源を宣言の順に返す(&self) -> impl Iterator<Item = 点光源入力> + '_ {
        self.枠.iter().flatten().map(|宣言| 宣言.点光源)
    }

    /// 局所光レコード列の書き込みが読む並び。影を落とさない灯は割り当てを持たない。
    pub(crate) fn 点光源と影の割り当てを宣言の順に返す(
        &self,
    ) -> impl Iterator<Item = (点光源入力, Option<影資源添字>)> + '_ {
        self.枠
            .iter()
            .flatten()
            .map(|宣言| (宣言.点光源, 宣言.影の割り当て.map(|割り当て| 割り当て.影資源添字)))
    }

    /// 影の描画計画。面ごとの描画パスの積み込みが読む並びであり、局所光レコード列の書き込みと同じ割り当てから出る。
    pub fn 影の描画計画を宣言の順に返す(&self) -> impl Iterator<Item = (影資源添字, 点光源入力, 投影の契約)> + '_ {
        self.枠
            .iter()
            .flatten()
            .filter_map(|宣言| 宣言.影の割り当て.map(|割り当て| (割り当て.影資源添字, 宣言.点光源, 割り当て.投影の契約)))
    }
}
