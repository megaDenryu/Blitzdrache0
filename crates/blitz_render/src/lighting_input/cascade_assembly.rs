//! ライティング入力のうち、カスケードの設定と組み立てだけを担当する。
//! 触れるフィールドは方向光・影・カスケード設定の3つに限り、点光源・環境光・有効には一切触れない。
//! 呼び出し頻度も他の操作と違い、毎フレーム1回の構築の局面でだけ呼ばれる。

use blitz_math::{クリップ, ワールド, 変換, 大域ワールド位置};

use super::{ライティング入力, ライティング入力エラー};
use crate::cascade::{カスケード一式, カスケード設定};

impl ライティング入力 {
    /// カスケードの設定だけを差し替えた値を返す。光と影の再構築パラメータは変えない。
    pub fn カスケード設定を差し替える(self, カスケード設定: カスケード設定) -> Self {
        Self {
            カスケード設定, ..self
        }
    }

    /// そのフレームのカスケードを、与えた原点の相対フレームで組み立てる。
    /// 距離区分ごとの行列・分割深度・距離区分別のライトビュー視錐台はすべてこの1つの結果から取る(単一正本の契約)。
    /// 同じ入力からは常に同じ結果が出るため、シェーダー定数書込と可視判定が別々に呼んでも同じ値を読む。
    /// 注意: 呼び出し元は対象の座標と同じカメラ大域原点と、そのカメラのカメラ相対ビュー射影を渡す責務を負う。
    pub fn カスケードを組み立てる(
        &self,
        相対フレーム原点: 大域ワールド位置,
        カメラ相対ビュー射影: 変換<ワールド, クリップ>,
    ) -> Result<カスケード一式, ライティング入力エラー> {
        crate::cascade::組み立てる(self.方向光, self.影.注視点(), 相対フレーム原点, カメラ相対ビュー射影, self.カスケード設定)
    }
}
