//! 方向光が影を落とすかどうかの判別。
//!
//! 影を落とさない状態を強度0で代用しないのは、光の強さと影の有無が別の概念であり、
//! 強度で代用すると「影だけを外す」条件を後から足せなくなるためである。

/// 方向光の影の落ち方。`落とさない`のとき、シーンのフラグメントはシャドウマップを1度も引かない。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 影の落ち方 {
    落とす,
    落とさない,
}

impl 影の落ち方 {
    pub(crate) fn 落とすか(self) -> bool {
        matches!(self, Self::落とす)
    }
}
