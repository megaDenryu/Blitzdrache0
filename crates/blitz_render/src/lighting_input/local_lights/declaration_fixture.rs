//! 局所光源列の検査が使う点光源の組み立て。担うのは、位置と影響半径と可視性だけを変えた1件を作ることである。
//! 検査そのものは持たない。

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};

use super::点光源入力;
use crate::clustered_lighting::影響半径;
use crate::lighting_input::{光強度, 光色, 点光源の可視性};

pub(super) fn 影なしの点光源を作る(x: f64) -> 点光源入力 {
    点光源を作る(x, 既定の半径(), 点光源の可視性::影なし)
}

pub(super) fn 影を落とす点光源を作る(x: f64) -> 点光源入力 {
    点光源を作る(x, 既定の半径(), 点光源の可視性::立方体影)
}

pub(super) fn 既定の半径() -> 影響半径 {
    影響半径::生成する(メートル::生成する(10.0)).unwrap_or_else(|誤り| panic!("検査の点光源を作れない: {誤り}"))
}

pub(super) fn 点光源を作る(x: f64, 半径: 影響半径, 可視性: 点光源の可視性) -> 点光源入力 {
    let 白 = 光色::生成する(1.0, 1.0, 1.0).unwrap_or_else(|誤り| panic!("検査の点光源を作れない: {誤り}"));
    let 強度 = 光強度::生成する(1.0).unwrap_or_else(|誤り| panic!("検査の点光源を作れない: {誤り}"));
    let 位置 = 大域ワールド位置::生成する(大域メートル::生成する(x), 大域メートル::生成する(0.0), 大域メートル::生成する(0.0));
    点光源入力::生成する(位置, 白, 強度, 半径, 可視性).unwrap_or_else(|誤り| panic!("検査の点光源を作れない: {誤り}"))
}
