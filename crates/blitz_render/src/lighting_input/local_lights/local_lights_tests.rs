//! 局所光源列が受理する件数の境界と、宣言の順が並びの順になることの検査。
//! 上限を型で保証できない入力(世界の宣言)を受け取る唯一の入口であるため、境界の両側をここで固定する。

#![allow(clippy::unwrap_used)]

use super::declaration_fixture::影なしの点光源を作る;
use super::{ライティング入力エラー, 局所光源列};

/// 上限までの宣言は通り、1件超えた宣言は件数を載せた型付きの失敗になる。
#[test]
fn 局所光源列は上限までを受理し超過を拒否する() {
    let 上限ちょうど = vec![影なしの点光源を作る(0.0); 局所光源列::上限件数];
    assert!(局所光源列::生成する(&上限ちょうど).is_ok());
    let 超過 = vec![影なしの点光源を作る(0.0); 局所光源列::上限件数 + 1];
    assert!(matches!(
        局所光源列::生成する(&超過),
        Err(ライティング入力エラー::局所光源列の件数が上限を超えた { 件数, 上限 })
            if 件数 == 局所光源列::上限件数 + 1 && 上限 == 局所光源列::上限件数
    ));
}

/// 宣言の順がそのまま並びの順であることを、位置のx成分で見る。件数0の列が0件を返すことも同時に固定する。
#[test]
fn 局所光源列は宣言の順に点光源を返す() {
    let 列 = 局所光源列::生成する(&[影なしの点光源を作る(1.0), 影なしの点光源を作る(2.0)]).unwrap();
    assert_eq!(列.件数(), 2);
    let 位置一覧: Vec<f64> = 列.点光源を宣言の順に返す().map(|光| 光.位置().x().値()).collect();
    assert_eq!(位置一覧, vec![1.0, 2.0]);
    assert_eq!(局所光源列::生成する(&[]).unwrap().件数(), 0);
}
