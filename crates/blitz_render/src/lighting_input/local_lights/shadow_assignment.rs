//! 宣言の並びから影の資源の割り当てを作る工程。受け取るのは宣言された点光源の並び、
//! 返すのは1件ごとの「立方体の番号と投影の契約」または型付きの失敗である。
//!
//! この工程が影資源添字の唯一の出どころである。世界が添字を宣言できる形にすると、2つの灯が同じ添字を
//! 宣言した状態を型が止められない。局所光レコード列の書き込みと面ごとの描画パスの積み込みは、
//! この工程が返した1つの並びを読む(参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断k」)。

use super::super::{ライティング入力エラー, 点光源入力};
use crate::point_light_shadow::{影を持てる灯の上限件数, 影資源添字, 投影の契約};

/// 影を落とす灯1件への、立方体の番号と投影の契約の割り当て。影を落とさない灯はこの値を持たない。
#[derive(Debug, Clone, Copy)]
pub(crate) struct 影を落とす灯の割り当て {
    pub(crate) 影資源添字: 影資源添字,
    pub(crate) 投影の契約: 投影の契約,
}

/// 宣言の順に0から番号を振る。影を落とす灯が上限を超えたら、件数と上限を添えた型付きの失敗にする。
/// 黙って上限まで切り詰めないのは、切り詰めると宣言が効いていないことを値から読めなくなるためである。
pub(crate) fn 宣言の順に影の資源を割り当てる(
    点光源一覧: &[点光源入力],
) -> Result<Vec<Option<影を落とす灯の割り当て>>, ライティング入力エラー> {
    let 影付きの件数 = 点光源一覧.iter().filter(|点光源| 点光源.可視性().影を落とすか()).count();
    if 影付きの件数 > 影を持てる灯の上限件数 {
        return Err(ライティング入力エラー::影を落とす点光源の件数が上限を超えた {
            件数: 影付きの件数,
            上限: 影を持てる灯の上限件数,
        });
    }
    let mut 割り当て一覧 = Vec::with_capacity(点光源一覧.len());
    let mut 影付きの順番 = 0usize;
    for 点光源 in 点光源一覧 {
        if !点光源.可視性().影を落とすか() {
            割り当て一覧.push(None);
            continue;
        }
        let 添字 = 影資源添字::宣言の順番から生成する(影付きの順番)
            .unwrap_or_else(|| panic!("影を落とす灯の順番{影付きの順番}が上限を超えた(件数の判定が破れている)"));
        割り当て一覧.push(Some(影を落とす灯の割り当て {
            影資源添字: 添字,
            投影の契約: 投影の契約::影響半径から生成する(点光源.影響半径())?,
        }));
        影付きの順番 += 1;
    }
    Ok(割り当て一覧)
}
