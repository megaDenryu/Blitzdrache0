//! 影の資源の割り当ての検査。影を落とす灯の件数の境界と、宣言の順に0から番号が割り当たることと、
//! 影を落とす灯の影響半径が近面以下なら宣言の時点で失敗することを見る。
//!
//! 割り当ての正本を1つに保つことがこの工程の担当であるため、局所光レコード列が読む並びと
//! 影の描画計画が読む並びが同じ番号を返すことも同時に固定する。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::declaration_fixture::{影なしの点光源を作る, 影を落とす点光源を作る, 点光源を作る};
use super::{ライティング入力エラー, 局所光源列};
use crate::clustered_lighting::影響半径;
use crate::lighting_input::点光源の可視性;
use crate::point_light_shadow::影を持てる灯の上限件数;

/// 影を落とす灯が0件でも上限件数でも受理し、1件超えたら件数と上限を載せた型付きの失敗になる。
#[test]
fn 影を落とす灯は上限件数までを受理し超過を拒否する() {
    assert!(
        局所光源列::生成する(&[影なしの点光源を作る(0.0)])
            .unwrap()
            .影の描画計画を宣言の順に返す()
            .next()
            .is_none()
    );
    let 上限ちょうど = vec![影を落とす点光源を作る(0.0); 影を持てる灯の上限件数];
    assert_eq!(
        局所光源列::生成する(&上限ちょうど).unwrap().影の描画計画を宣言の順に返す().count(),
        影を持てる灯の上限件数
    );
    let 超過 = vec![影を落とす点光源を作る(0.0); 影を持てる灯の上限件数 + 1];
    assert!(matches!(
        局所光源列::生成する(&超過),
        Err(ライティング入力エラー::影を落とす点光源の件数が上限を超えた { 件数, 上限 })
            if 件数 == 影を持てる灯の上限件数 + 1 && 上限 == 影を持てる灯の上限件数
    ));
}

/// 影資源添字は影を落とす灯だけへ宣言の順に0から割り当たり、影なしの灯は間を飛ばさない。
#[test]
fn 影資源添字は影を落とす灯へ宣言の順に0から割り当たる() {
    let 宣言 = [
        影なしの点光源を作る(0.0),
        影を落とす点光源を作る(1.0),
        影なしの点光源を作る(2.0),
        影を落とす点光源を作る(3.0),
    ];
    let 列 = 局所光源列::生成する(&宣言).unwrap();
    let 計画: Vec<(u32, f64)> = 列
        .影の描画計画を宣言の順に返す()
        .map(|(添字, 点光源, _)| (添字.値(), 点光源.位置().x().値()))
        .collect();
    assert_eq!(計画, vec![(0, 1.0), (1, 3.0)]);
    let 割り当て: Vec<Option<u32>> = 列
        .点光源と影の割り当てを宣言の順に返す()
        .map(|(_, 添字)| 添字.map(|添字| 添字.値()))
        .collect();
    assert_eq!(割り当て, vec![None, Some(0), None, Some(1)]);
}

/// 影を落とす灯の影響半径が近面以下なら、宣言の時点で型付きの失敗になる。影なしの灯は同じ半径でも通る。
#[test]
fn 影を落とす灯の影響半径が近面以下なら宣言を拒否する() {
    let 極小の半径 = 影響半径::生成する(メートル::生成する(0.01)).unwrap();
    let 影あり = 点光源を作る(0.0, 極小の半径, 点光源の可視性::立方体影);
    assert!(matches!(
        局所光源列::生成する(&[影あり]),
        Err(ライティング入力エラー::影を落とす点光源の宣言が不正(_))
    ));
    let 影なし = 点光源を作る(0.0, 極小の半径, 点光源の可視性::影なし);
    assert!(局所光源列::生成する(&[影なし]).is_ok());
}
