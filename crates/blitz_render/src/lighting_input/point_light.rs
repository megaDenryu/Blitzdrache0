//! 点光源の型付き入力。位置から全方向へ光を出し、距離で減衰する光を表す。

use blitz_math::大域ワールド位置;

use super::{ライティング入力エラー, 光強度, 光色, 点光源の可視性};
use crate::clustered_lighting::影響半径;

/// 位置は大域ワールド位置で持つ。カメラ相対フレームへの狭めは毎フレームのUBO書き込みが行うため、ここでは大きな座標のまま保つ。
///
/// 影響半径を必須で持つのは、光が届く範囲が光を置く側の設計値だからである。強度と打ち切りの閾値からの導出値にすると、
/// 明るさを調整しただけで届く範囲が黙って変わり、クラスタ格子のセルへの割り当てまで一緒に動く
/// (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断a: 影響半径は点光源入力の必須フィールドとし、強度からの導出値にしない」)。
///
/// 可視性も必須で持つ。既定値を置かない理由は`点光源の可視性`が持つ(判断k)。
#[derive(Debug, Clone, Copy)]
pub struct 点光源入力 {
    位置: 大域ワールド位置,
    色: 光色,
    強度: 光強度,
    影響半径: 影響半径,
    可視性: 点光源の可視性,
}

impl 点光源入力 {
    pub fn 生成する(
        位置: 大域ワールド位置,
        色: 光色,
        強度: 光強度,
        影響半径: 影響半径,
        可視性: 点光源の可視性,
    ) -> Result<Self, ライティング入力エラー> {
        if [位置.x().値(), 位置.y().値(), 位置.z().値()].iter().any(|成分| !成分.is_finite()) {
            return Err(ライティング入力エラー::点光源位置不正);
        }
        Ok(Self {
            位置,
            色,
            強度,
            影響半径,
            可視性,
        })
    }

    pub(crate) fn 可視性(self) -> 点光源の可視性 {
        self.可視性
    }

    pub fn 位置(self) -> 大域ワールド位置 {
        self.位置
    }

    pub(crate) fn 影響半径(self) -> 影響半径 {
        self.影響半径
    }

    pub(crate) fn 色(self) -> [f32; 3] {
        self.色.配列()
    }

    pub(crate) fn 強度(self) -> f32 {
        self.強度.値()
    }
}
