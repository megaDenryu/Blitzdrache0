//! 分割深度と境界ブレンドの検査。分割深度が単調で距離区分の区間に隙間が無いこと、遷移域の重みが単調で和が1に
//! なることを見る。

use super::super::band::距離区分番号;
use super::super::settings::多段設定;
use super::super::{blend, split, 距離区分の境界数};
use super::m;

#[test]
fn 分割深度が単調で距離区分の区間に隙間が無い() {
    let 分割 = split::分割する(m(0.1), m(300.0), 多段設定::既定());
    for 添字 in 1..距離区分の境界数 {
        assert!(
            分割.分割深度[添字 - 1].値() < 分割.分割深度[添字].値(),
            "分割深度が単調でない: {:?}",
            分割.分割深度.map(|深度| 深度.値())
        );
    }
    for 番号 in 距離区分番号::全距離区分() {
        let 区間 = 分割.距離区分の区間一覧[番号.添字()];
        assert!(区間.近深度().値() < 区間.遠深度().値());
        if 番号.添字() > 0 {
            let 手前 = 分割.距離区分の区間一覧[番号.添字() - 1];
            assert!(区間.近深度().値() <= 手前.遠深度().値(), "距離区分{}の手前に隙間がある", 番号.添字());
            assert!(区間.近深度().値() < 手前.遠深度().値(), "距離区分{}が手前と重なっていない", 番号.添字());
        }
    }
}

#[test]
fn 境界ブレンドの重みが単調で和が1になる() {
    let 分割 = split::分割する(m(0.1), m(300.0), 多段設定::既定());
    let mut 直前の主重み = f32::MAX;
    let mut 直前の主距離区分 = 0;
    let mut 深度値 = 0.1_f32;
    while 深度値 < 320.0 {
        深度値 += 0.05;
        let ブレンド = blend::距離区分を選ぶ(m(深度値), 分割.分割深度, 分割.遷移幅);
        assert!((0.0..=1.0).contains(&ブレンド.主重み), "主重みが0から1の外: {}", ブレンド.主重み);
        let 和 = ブレンド.主重み + (1.0 - ブレンド.主重み);
        assert!((和 - 1.0).abs() < 1.0e-6, "重みの和が1でない: {和}");
        if ブレンド.主距離区分.添字() == 直前の主距離区分 && ブレンド.副距離区分.添字() != ブレンド.主距離区分.添字()
        {
            assert!(ブレンド.主重み <= 直前の主重み + 1.0e-6, "遷移域の中で主重みが増えた");
        }
        直前の主重み = ブレンド.主重み;
        直前の主距離区分 = ブレンド.主距離区分.添字();
    }
}
