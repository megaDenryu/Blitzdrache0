//! テクセルスナップの契約の検査。担当するのは、静止した大域点の光源テクセル座標がカメラの微小移動で動かないこと
//! (本番と同じ合成経路で見る)と、刻みを超える移動でスナップ済み中心が整数テクセル刻みで動くことの2つである。
//!
//! カメラ相対描画では相対フレーム原点が動けば行列そのものは変わる。同じ静止物の相対座標も逆向きに変わるため、
//! 不変なのは行列でなく両者を合成した光源クリップ座標である。したがって前者は行列単体でなく合成結果で見る。

use blitz_math::{ワールド, 位置, 大域ワールド位置};

use super::super::band::距離区分番号;
use super::super::resolution::影の一辺解像度;
use super::super::settings::多段設定;
use super::super::{snap, 多段一式, 組み立てる};
use super::{m, ビュー射影, 大域, 方向光};

/// 同じテクセルへ落ちたとみなす許容差(テクセル)。行列と相対座標をf32で組み立てる経路の丸めだけを許し、
/// スナップが無いときに出るずれは許さない値を置く。実測では、スナップ有りの距離区分間最大のずれが0.00012テクセル、
/// スナップを止めたときの距離区分0のずれが0.024テクセルであり、この値は両者のおよそ中間(対数尺度)にある。
const テクセル座標の許容差: f64 = 2.0e-3;

/// 影を落とす静止物の代表点(大域座標)。カメラの手前十数メートルに置き、最も刻みの細かい距離区分0の正射影へ入れる。
fn 静止物一覧() -> [大域ワールド位置; 3] {
    [大域(52.0, 2.0, -25.0), 大域(47.0, 3.5, -28.0), 大域(56.0, 5.0, -31.0)]
}

#[test]
fn 一テクセル未満のカメラ移動で静止物の光源テクセル座標が変わらない() {
    let 基準 = 大域(0.0, 0.0, 0.0);
    let 元原点 = 大域(50.0, 3.0, -20.0);
    // 既定設定のこの視錐台では距離区分0の1テクセルが0.035メートル、距離区分3でも0.35メートルであるため、1ミリメートルの移動はどの距離区分でも1テクセル未満である。
    let 移動後原点 = 元原点.平行移動する(大域(0.001, 0.0, 0.0));
    let 元 = 組み立てる(方向光(), 基準, 元原点, ビュー射影(), 多段設定::既定()).unwrap();
    let 移動後 = 組み立てる(方向光(), 基準, 移動後原点, ビュー射影(), 多段設定::既定()).unwrap();
    for 番号 in 距離区分番号::全距離区分() {
        for 静止物 in 静止物一覧() {
            let 元座標 = テクセル座標(&元, 番号, 元原点, 静止物);
            let 後座標 = テクセル座標(&移動後, 番号, 移動後原点, 静止物);
            for (軸, (元値, 後値)) in 元座標.iter().zip(後座標.iter()).enumerate() {
                assert!(
                    (元値 - 後値).abs() < テクセル座標の許容差,
                    "距離区分{}の静止物のテクセル座標が1テクセル未満の移動で動いた(軸{軸}): {元値} と {後値}",
                    番号.添字()
                );
            }
        }
    }
}

#[test]
fn 閾値を超えた移動でスナップ済み中心が整数テクセル刻みで動く() {
    let 基準 = 大域(0.0, 0.0, 0.0);
    let 刻み = m(0.25);
    let 元位置 = 大域(13.3, -4.1, 7.9);
    let 元 = snap::光空間の格子へ寄せる(元位置, 基準, 方向光().方向(), 刻み);
    // 刻みより十分大きい移動。光空間の各軸で見たとき、寄せた後の位置は刻みの整数倍だけ動く。
    let 後 = snap::光空間の格子へ寄せる(元位置.平行移動する(大域(3.7, 1.1, -2.4)), 基準, 方向光().方向(), 刻み);
    let 元成分 = 光空間の成分(元, 基準, 方向光().方向());
    let 後成分 = 光空間の成分(後, 基準, 方向光().方向());
    let mut 動いた軸数 = 0;
    for (後値, 元値) in 後成分.iter().zip(元成分.iter()) {
        let 商 = (後値 - 元値) / f64::from(刻み.値());
        assert!((商 - 商.round()).abs() < 1.0e-6, "スナップ後の移動量が整数テクセル刻みでない: {商}");
        if 商.round().abs() >= 1.0 {
            動いた軸数 += 1;
        }
    }
    assert!(動いた軸数 > 0, "刻みを超える移動でスナップ済み中心が1軸も動かなかった");
}

/// 大域点を本番と同じ経路(相対フレームへ落としてから距離区分の行列を掛ける)で光源クリップへ写し、XYをテクセルで数える。
/// 光源クリップの[-1,1]がシャドウマップの一辺に対応するため、テクセル座標は(成分 × 0.5 + 0.5) × 一辺のテクセル数である。
fn テクセル座標(
    一式: &多段一式, 番号: 距離区分番号, 相対フレーム原点: 大域ワールド位置, 静止物: 大域ワールド位置
) -> [f64; 2] {
    let 行列 = 一式.距離区分のライトビュー射影(番号, 相対フレーム原点).unwrap();
    let 相対 = 静止物.カメラ相対へ変換する(相対フレーム原点).unwrap();
    let 相対位置: 位置<ワールド> = 位置::生成する(相対.x(), 相対.y(), 相対.z());
    let 写像 = 行列.適用する(相対位置);
    let 解像度 = f64::from(影の一辺解像度::既定().テクセル数());
    [
        (f64::from(写像.x().値()) * 0.5 + 0.5) * 解像度,
        (f64::from(写像.y().値()) * 0.5 + 0.5) * 解像度,
    ]
}

fn 光空間の成分(位置: 大域ワールド位置, 基準: 大域ワールド位置, 光の向き: [f32; 3]) -> [f64; 3] {
    let 前 = glam::DVec3::new(f64::from(光の向き[0]), f64::from(光の向き[1]), f64::from(光の向き[2])).normalize();
    let 右 = 前.cross(glam::DVec3::Y).normalize();
    let 上 = 右.cross(前);
    let ずれ = glam::DVec3::new(位置.x().値(), 位置.y().値(), 位置.z().値()) - glam::DVec3::new(基準.x().値(), 基準.y().値(), 基準.z().値());
    [ずれ.dot(右), ずれ.dot(上), ずれ.dot(前)]
}
