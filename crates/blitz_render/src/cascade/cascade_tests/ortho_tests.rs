//! 距離区分の正射影がカメラ視錐台のスライスを覆うことと、カメラ相対契約の検査。スライスの8隅が正射影に収まること、
//! 大域原点を平行移動しても同じ相対フレームで見た行列が変わらないことを見る。

use super::super::band::距離区分番号;
use super::super::settings::カスケード設定;
use super::super::組み立てる;
use super::{ビュー射影, 大域, 方向光};

#[test]
fn スライスの8隅が距離区分の正射影の内側に収まる() {
    let 原点 = 大域(1234.0, 56.0, -789.0);
    let 基準 = 大域(1200.0, 0.0, -800.0);
    let 一式 = 組み立てる(方向光(), 基準, 原点, ビュー射影(), カスケード設定::既定()).unwrap();
    for 番号 in 距離区分番号::全距離区分() {
        let 行列 = 一式.距離区分のライトビュー射影(番号, 原点).unwrap();
        for 隅 in 一式.隅一覧(番号) {
            let 写像 = 行列.適用する(隅);
            let (x, y, z) = (写像.x().値(), 写像.y().値(), 写像.z().値());
            assert!(x.abs() <= 1.0, "距離区分{:?}の隅のxが範囲外: {x}", 番号.添字());
            assert!(y.abs() <= 1.0, "距離区分{:?}の隅のyが範囲外: {y}", 番号.添字());
            assert!((0.0..=1.0).contains(&z), "距離区分{:?}の隅のzが範囲外: {z}", 番号.添字());
        }
    }
}

#[test]
fn 大域原点の平行移動で距離区分の行列が変わらない() {
    let ずれ = 大域(120_000.0, -3_000.0, 45_000.0);
    let (原点, 基準) = (大域(10.0, 2.0, -30.0), 大域(0.0, 0.0, 0.0));
    let (移動後原点, 移動後基準) = (原点.平行移動する(ずれ), 基準.平行移動する(ずれ));
    let 元 = 組み立てる(方向光(), 基準, 原点, ビュー射影(), カスケード設定::既定()).unwrap();
    let 移動後 = 組み立てる(方向光(), 移動後基準, 移動後原点, ビュー射影(), カスケード設定::既定()).unwrap();
    for 番号 in 距離区分番号::全距離区分() {
        let 元行列 = 元.距離区分のライトビュー射影(番号, 原点).unwrap().gpu境界用列優先配列();
        let 後行列 = 移動後.距離区分のライトビュー射影(番号, 移動後原点).unwrap().gpu境界用列優先配列();
        for (元列, 後列) in 元行列.iter().zip(後行列.iter()) {
            for (元値, 後値) in 元列.iter().zip(後列.iter()) {
                assert!(
                    (元値 - 後値).abs() < 1.0e-3,
                    "距離区分{}の行列が原点移動で変わった: {元値} と {後値}",
                    番号.添字()
                );
            }
        }
    }
}
