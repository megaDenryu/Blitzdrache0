//! 帯の正射影とテクセルスナップの検査。スライスの8隅が正射影に収まること、大域原点の平行移動で行列が
//! 変わらないこと、1テクセル未満のカメラ移動で行列が変わらず閾値超過で整数テクセル刻みで動くことを見る。

use blitz_math::大域ワールド位置;

use super::super::band::帯番号;
use super::super::settings::カスケード設定;
use super::super::{snap, 組み立てる};
use super::{m, ビュー射影, 大域, 方向光};

#[test]
fn スライスの8隅が帯の正射影の内側に収まる() {
    let 原点 = 大域(1234.0, 56.0, -789.0);
    let 基準 = 大域(1200.0, 0.0, -800.0);
    let 一式 = 組み立てる(方向光(), 基準, 原点, ビュー射影(), カスケード設定::既定()).unwrap();
    for 番号 in 帯番号::全帯() {
        let 行列 = 一式.帯のライトビュー射影(番号, 方向光(), 原点).unwrap();
        for 隅 in 一式.隅一覧(番号) {
            let 写像 = 行列.適用する(隅);
            let (x, y, z) = (写像.x().値(), 写像.y().値(), 写像.z().値());
            assert!(x.abs() <= 1.0, "帯{:?}の隅のxが範囲外: {x}", 番号.添字());
            assert!(y.abs() <= 1.0, "帯{:?}の隅のyが範囲外: {y}", 番号.添字());
            assert!((0.0..=1.0).contains(&z), "帯{:?}の隅のzが範囲外: {z}", 番号.添字());
        }
    }
}

#[test]
fn 大域原点の平行移動で帯の行列が変わらない() {
    let ずれ = 大域(120_000.0, -3_000.0, 45_000.0);
    let (原点, 基準) = (大域(10.0, 2.0, -30.0), 大域(0.0, 0.0, 0.0));
    let (移動後原点, 移動後基準) = (原点.平行移動する(ずれ), 基準.平行移動する(ずれ));
    let 元 = 組み立てる(方向光(), 基準, 原点, ビュー射影(), カスケード設定::既定()).unwrap();
    let 移動後 = 組み立てる(方向光(), 移動後基準, 移動後原点, ビュー射影(), カスケード設定::既定()).unwrap();
    for 番号 in 帯番号::全帯() {
        let 元行列 = 元.帯のライトビュー射影(番号, 方向光(), 原点).unwrap().gpu境界用列優先配列();
        let 後行列 = 移動後.帯のライトビュー射影(番号, 方向光(), 移動後原点).unwrap().gpu境界用列優先配列();
        for (元列, 後列) in 元行列.iter().zip(後行列.iter()) {
            for (元値, 後値) in 元列.iter().zip(後列.iter()) {
                assert!(
                    (元値 - 後値).abs() < 1.0e-3,
                    "帯{}の行列が原点移動で変わった: {元値} と {後値}",
                    番号.添字()
                );
            }
        }
    }
}

#[test]
fn 一テクセル未満のカメラ移動でスナップ済み行列が変わらない() {
    let 基準 = 大域(0.0, 0.0, 0.0);
    let 原点 = 大域(50.0, 3.0, -20.0);
    // 帯0の1テクセルはおよそ0.02メートルであるため、1ミリメートルの移動はどの帯でも1テクセル未満である。
    let 微小移動 = 大域(0.001, 0.0, 0.0);
    let 元 = 組み立てる(方向光(), 基準, 原点, ビュー射影(), カスケード設定::既定()).unwrap();
    let 移動後 = 組み立てる(方向光(), 基準, 原点.平行移動する(微小移動), ビュー射影(), カスケード設定::既定()).unwrap();
    for 番号 in 帯番号::全帯() {
        let 元行列 = 元.帯のライトビュー射影(番号, 方向光(), 基準).unwrap();
        let 後行列 = 移動後.帯のライトビュー射影(番号, 方向光(), 基準).unwrap();
        assert_eq!(元行列, 後行列, "帯{}の行列が1テクセル未満の移動で変わった", 番号.添字());
    }
}

#[test]
fn 閾値を超えた移動でスナップ済み中心が整数テクセル刻みで動く() {
    let 基準 = 大域(0.0, 0.0, 0.0);
    let 刻み = m(0.25);
    let 元位置 = 大域(13.3, -4.1, 7.9);
    let 元 = snap::光空間の格子へ寄せる(元位置, 基準, 方向光().方向(), 刻み);
    // 刻みより十分大きい移動。光空間の各軸で見たとき、寄せた後の位置は刻みの整数倍だけ動く。
    let 後 = snap::光空間の格子へ寄せる(元位置.平行移動する(大域(3.7, 1.1, -2.4)), 基準, 方向光().方向(), 刻み);
    let 元成分 = 光空間の成分(元, 基準, 方向光().方向());
    let 後成分 = 光空間の成分(後, 基準, 方向光().方向());
    let mut 動いた軸数 = 0;
    for (後値, 元値) in 後成分.iter().zip(元成分.iter()) {
        let 商 = (後値 - 元値) / f64::from(刻み.値());
        assert!((商 - 商.round()).abs() < 1.0e-6, "スナップ後の移動量が整数テクセル刻みでない: {商}");
        if 商.round().abs() >= 1.0 {
            動いた軸数 += 1;
        }
    }
    assert!(動いた軸数 > 0, "刻みを超える移動でスナップ済み中心が1軸も動かなかった");
}

fn 光空間の成分(位置: 大域ワールド位置, 基準: 大域ワールド位置, 光の向き: [f32; 3]) -> [f64; 3] {
    let 前 = glam::DVec3::new(f64::from(光の向き[0]), f64::from(光の向き[1]), f64::from(光の向き[2])).normalize();
    let 右 = 前.cross(glam::DVec3::Y).normalize();
    let 上 = 右.cross(前);
    let ずれ = glam::DVec3::new(位置.x().値(), 位置.y().値(), 位置.z().値()) - glam::DVec3::new(基準.x().値(), 基準.y().値(), 基準.z().値());
    [ずれ.dot(右), ずれ.dot(上), ずれ.dot(前)]
}
