//! 明示の境界で分けたときの分割深度と、境界の並びが満たすべき不変条件の反証。

use blitz_math::メートル;

use super::super::band::距離区分番号;
use super::super::band_assignment::距離区分の割り当て;
use super::super::explicit_boundaries::明示の距離区分境界;
use super::super::settings::多段設定;
use super::super::{split, 距離区分の境界数};
use super::m;

/// 大規模世界の境界。第1区分が接地影、第2区分が1チャンク、第3区分が先読み層、第4区分が遠景層を担当する。
/// 参照: `_doc/設計/大規模世界の生成と遠景.md`「大規模世界だけは明示境界25メートル・100メートル・1000メートル・10000メートルを使い」
fn 大規模世界の設定() -> 多段設定 {
    let 境界 = 明示の距離区分境界::生成する([m(25.0), m(100.0), m(1000.0)]).unwrap_or_else(|誤り| panic!("{誤り}"));
    let 割り当て = 距離区分の割り当て::明示の境界で分ける(境界, m(10000.0)).unwrap_or_else(|誤り| panic!("{誤り}"));
    多段設定::既定().割り当てを差し替える(割り当て)
}

#[test]
fn 名指しの境界がそのまま分割深度になる() {
    let 分割 = split::分割する(m(0.1), m(10000.0), 大規模世界の設定());
    let 実際 = 分割.分割深度.map(|深度| 深度.値());
    assert_eq!(実際, [25.0, 100.0, 1000.0]);
}

/// 最大影距離だけを10000メートルへ替えた実用分割は境界が約1001・2019・3337メートルになり、近景の3区分を失う。
/// 明示の境界を入れた理由そのものであるため、2つが確かに違う結果を出すことを反証として残す。
#[test]
fn 実用分割では近景の三区分が失われる() {
    let 実用分割の設定 = 多段設定::既定().割り当てを差し替える(
        距離区分の割り当て::既定()
            .最大影距離を差し替える(m(10000.0))
            .unwrap_or_else(|誤り| panic!("{誤り}")),
    );
    let 分割 = split::分割する(m(0.1), m(10000.0), 実用分割の設定);
    assert!(
        分割.分割深度[0].値() > 500.0,
        "実用分割の第1境界が近景に留まっている: {}",
        分割.分割深度[0].値()
    );
}

/// 重なりは分け方に依らず同じ率で効く。明示の境界でも距離区分の区間は手前へ伸びる。
#[test]
fn 明示の境界でも距離区分は手前と重なる() {
    let 分割 = split::分割する(m(0.1), m(10000.0), 大規模世界の設定());
    for 番号 in 距離区分番号::全距離区分() {
        let 区間 = 分割.距離区分の区間一覧[番号.添字()];
        assert!(区間.近深度().値() < 区間.遠深度().値(), "距離区分{}の区間が反転した", 番号.添字());
        if 番号.添字() > 0 {
            let 手前 = 分割.距離区分の区間一覧[番号.添字() - 1];
            assert!(区間.近深度().値() < 手前.遠深度().値(), "距離区分{}が手前と重なっていない", 番号.添字());
        }
    }
    for 添字 in 0..距離区分の境界数 {
        assert!(分割.遷移幅[添字].値() > 0.0, "境界{添字}の遷移幅が0である");
    }
}

#[test]
fn 単調でない境界を拒む() {
    assert!(明示の距離区分境界::生成する([m(100.0), m(25.0), m(1000.0)]).is_err());
    assert!(明示の距離区分境界::生成する([m(25.0), m(25.0), m(1000.0)]).is_err());
    assert!(明示の距離区分境界::生成する([m(-1.0), m(25.0), m(1000.0)]).is_err());
    assert!(明示の距離区分境界::生成する([m(25.0), m(100.0), m(f32::INFINITY)]).is_err());
}

#[test]
fn 最大影距離を超える境界を拒む() {
    let 境界 = 明示の距離区分境界::生成する([m(25.0), m(100.0), m(1000.0)]).unwrap_or_else(|誤り| panic!("{誤り}"));
    assert!(距離区分の割り当て::明示の境界で分ける(境界, m(1000.0)).is_err());
    assert!(距離区分の割り当て::明示の境界で分ける(境界, m(900.0)).is_err());
    assert!(距離区分の割り当て::明示の境界で分ける(境界, m(1000.1)).is_ok());
}

/// 遠クリップが境界より手前にある構成では、境界を遠深度で止めて区間の反転を防ぐ。
#[test]
fn 遠深度より奥の境界は遠深度で止まる() {
    let 分割 = split::分割する(m(0.1), メートル::生成する(500.0), 大規模世界の設定());
    let 実際 = 分割.分割深度.map(|深度| 深度.値());
    assert_eq!(実際, [25.0, 100.0, 500.0]);
    for 番号 in 距離区分番号::全距離区分() {
        let 区間 = 分割.距離区分の区間一覧[番号.添字()];
        assert!(区間.近深度().値() <= 区間.遠深度().値(), "距離区分{}の区間が反転した", 番号.添字());
    }
}
