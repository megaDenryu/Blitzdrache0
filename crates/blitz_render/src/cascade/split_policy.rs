//! 距離区分の境界をどう決めるかの2通り。実用分割は近深度と最大影距離から境界を計算し、
//! 明示の境界は設計が名指しした距離をそのまま使う。
//!
//! 判別共用体で表すのは、2つが「同じ計算の引数違い」ではなく別の決め方だからである。混合率と境界の並びを
//! 両方持つ設定にすると、どちらが効いているのかが値からは読めず、片方だけを直した食い違いが絵に出ない。
//!
//! 重なり率とキャスター余白と解像度はどちらの決め方でも同じに効くため、この共用体は境界の決め方だけを持つ。

use super::explicit_boundaries::明示の距離区分境界;
use super::ratio::実用分割混合率;

/// 距離区分の境界の決め方。
#[derive(Debug, Clone, Copy)]
pub enum 距離区分の分け方 {
    /// 一様分割と対数分割を混ぜて境界を計算する。世界の構造と距離区分の担当を対応させる必要が無い世界の既定である。
    実用分割(実用分割混合率),
    /// 設計が名指しした境界をそのまま使う。距離区分の担当が世界の構造で決まる世界が選ぶ。
    明示の境界(明示の距離区分境界),
}
