//! カスケード1式を組み立てる工程。受け取るのは方向光・格子の基準点・カメラ大域原点・カメラ相対ビュー射影・設定、
//! 返すのは帯ごとの正射影・分割深度・遷移幅を束ねた`カスケード一式`である。
//! 同じ入力からは常に同じ結果が出る純関数であり、ユニフォーム書込と可視判定はこの関数を通して同じ値を読む。

use blitz_math::{クリップ, メートル, ワールド, 位置, 変換, 大域メートル, 大域ワールド位置};

use super::band::帯番号;
use super::camera_frustum::カメラ視錐台;
use super::cascade_set::カスケード一式;
use super::settings::カスケード設定;
use super::{bounding, ortho, snap, split, 帯数, 帯解像度};
use crate::lighting_input::{ライティング入力エラー, 影入力, 方向光入力};

pub(crate) fn 組み立てる(
    方向光: 方向光入力,
    格子の基準点: 大域ワールド位置,
    カメラ大域原点: 大域ワールド位置,
    カメラ相対ビュー射影: 変換<ワールド, クリップ>,
    設定: カスケード設定,
) -> Result<カスケード一式, ライティング入力エラー> {
    let 零 = メートル::生成する(0.0);
    let 視錐台 = カメラ視錐台::復元する(カメラ相対ビュー射影).ok_or(ライティング入力エラー::カスケード視錐台不正)?;
    let 軸 = 視錐台.軸();
    let 遠深度 = if 設定.最大影距離() < 軸.遠深度 {
        設定.最大影距離()
    } else {
        軸.遠深度
    };
    if 遠深度.値() <= 軸.近深度.値() {
        return Err(ライティング入力エラー::カスケード視錐台不正);
    }
    let 分割 = split::分割する(軸.近深度, 遠深度, 設定);

    let mut 帯一覧: Vec<影入力> = Vec::with_capacity(帯数);
    let mut 隅一覧 = [[位置::<ワールド>::生成する(零, 零, 零); 8]; 帯数];
    for 番号 in 帯番号::全帯() {
        隅一覧[番号.添字()] = 視錐台.スライスの隅(分割.帯区間一覧[番号.添字()]);
        let 球 = bounding::包囲球を求める(&軸, 分割.帯区間一覧[番号.添字()]);
        let 半幅 = メートル::生成する(球.半径 * 半幅の余裕倍率());
        let 刻み = メートル::生成する(半幅.値() * 2.0 / f32::from(u16::try_from(帯解像度).unwrap_or(u16::MAX)));
        let 中心 = カメラ大域原点.平行移動する(大域ワールド位置::生成する(
            大域メートル::生成する(f64::from(球.中心.x)),
            大域メートル::生成する(f64::from(球.中心.y)),
            大域メートル::生成する(f64::from(球.中心.z)),
        ));
        let 寄せた中心 = snap::光空間の格子へ寄せる(中心, 格子の基準点, 方向光.方向(), 刻み);
        let 奥行き半幅 = メートル::生成する(球.半径);
        帯一覧.push(ortho::正射影を作る(寄せた中心, 半幅, 半幅, 奥行き半幅, 設定.キャスター余白())?);
    }

    Ok(カスケード一式 {
        方向光,
        帯一覧: 配列にする(帯一覧),
        区間一覧: 分割.帯区間一覧,
        分割深度: 分割.分割深度,
        遷移幅: 分割.遷移幅,
        隅一覧,
        カメラ前方: [軸.前方.x, 軸.前方.y, 軸.前方.z],
    })
}

/// 正射影の半幅を包囲球の半径より1テクセルぶん広く取る倍率。テクセルスナップで中心が最大で半テクセル動くため、
/// 余裕が無いとスライスの隅が正射影の外へわずかにはみ出す。
fn 半幅の余裕倍率() -> f32 {
    1.0 + 2.0 / f32::from(u16::try_from(帯解像度).unwrap_or(u16::MAX))
}

fn 配列にする(一覧: Vec<影入力>) -> [影入力; 帯数] {
    <[影入力; 帯数]>::try_from(一覧).unwrap_or_else(|_| panic!("帯の構築結果が帯数と一致しない(実装のバグ)"))
}
