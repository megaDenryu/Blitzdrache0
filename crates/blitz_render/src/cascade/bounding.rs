//! 帯のスライスを包む球を、視錐台の軸と深度区間から閉じた式で求める工程。
//! 受け取るのは視錐台の軸と帯区間、返すのはカメラ相対フレームの球の中心と半径である。
//!
//! 隅の座標から包囲球を数値的に求めず閉じた式で求めるのは、半径がカメラの向きに依らない値でなければ
//! ならないためである。半径が向きで揺れると正射影の1テクセルの世界幅も揺れ、テクセルスナップが
//! 意味を失う(スナップ後も格子そのものが毎フレーム伸縮する)。

use glam::Vec3;

use super::band::帯区間;
use super::camera_frustum::視錐台の軸;

pub(super) struct 帯の包囲球 {
    pub(super) 中心: Vec3,
    pub(super) 半径: f32,
}

/// 視軸上の点を中心に、スライスの近隅8点と遠隅8点をすべて含む最小の球を求める。
/// 半径比を a、区間の近深度を n、遠深度を f とすると、中心の深度は (n + f)(a² + 1) / 2 である
/// (近隅までの距離と遠隅までの距離が等しくなる条件を解いた結果)。
/// この深度が f を超えるときは遠隅が支配的であり、中心を遠平面へ置いて半径 f·a を取る。
pub(super) fn 包囲球を求める(軸: &視錐台の軸, 区間: 帯区間) -> 帯の包囲球 {
    let a = 軸.半径比;
    let 近 = 区間.近深度().値();
    let 遠 = 区間.遠深度().値();
    let 中心深度候補 = (近 + 遠) * (a * a + 1.0) * 0.5;
    let (中心深度, 半径) = if 中心深度候補 > 遠 {
        (遠, 遠 * a)
    } else {
        let 遠へのずれ = 中心深度候補 - 遠;
        ((中心深度候補), (遠 * 遠 * a * a + 遠へのずれ * 遠へのずれ).sqrt())
    };
    帯の包囲球 {
        中心: 軸.前方 * 中心深度,
        半径,
    }
}
