//! 距離区分ごとのシャドウマップの解像度密度。担当するのは「1テクセルが世界で覆う長さを距離区分の数だけ束ねて運ぶ」ことである。
//! 触れる値は構築時に決まった長さの配列だけであり、作れるのは多段の構築だけに限る。
//!
//! 生の配列でなく型で包むのは、この値が「メートル毎テクセル」という単位を持つ量であり、
//! 分割深度や遷移幅と同じ`[メートル; 距離区分数]`と取り違えるとどちらもコンパイルが通ってしまうためである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「予算」

use blitz_math::メートル;

use super::距離区分数;

#[derive(Debug, Clone, Copy)]
pub struct 影の解像度密度([メートル; 距離区分数]);

impl 影の解像度密度 {
    pub(super) fn 生成する(距離区分ごと: [メートル; 距離区分数]) -> Self {
        Self(距離区分ごと)
    }

    /// 距離区分番号の昇順に並んだ、1テクセルが世界で覆う長さ。報告と予算の突き合わせがこの並びを読む。
    pub fn 距離区分ごとの世界メートル毎テクセル(self) -> [メートル; 距離区分数] {
        self.0
    }
}
