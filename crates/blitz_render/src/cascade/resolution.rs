//! 距離区分1枚あたりのシャドウマップの一辺の長さをテクセル数で表す値。
//! 担当するのは「その値が2の冪でありu16の範囲に収まる」という2つの不変条件を保つことである。
//! 触れる値はテクセル数1つだけであり、生成の検証と3つの読み出し以外の操作を持たない。
//!
//! 生の`u32`で持たない理由は2つある。テクセルスナップの刻み・正射影の半幅の余裕・シャドウマップ資源の寸法・
//! PCFのテクセル尺度がすべてこの1つの値から導かれるため、途中で別の数と取り違えると報告の値と実際に描いた
//! 範囲が黙ってずれる。もう1つは、2の冪であることがテクセル尺度(逆数)をf32で誤差なく表せる根拠だからである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「多段シャドウ(CSM)」

use crate::lighting_input::ライティング入力エラー;

/// 本番の既定値。設計正本が品質要件として置いた距離区分あたり2048である。
const 既定のテクセル数: u16 = 2048;
/// 受け付ける下限。これより粗いと最も手前の距離区分でも影の輪郭がテクセルの塊になる。
const 下限のテクセル数: u16 = 256;
/// 受け付ける上限。1層あたり4バイトのD32を距離区分4層ぶん確保するため、4096で4096×4096×4×4=256メビバイトになる。
/// 8192は同じ計算で1ギビバイトへ跳ね、律速の切り分けに要る値でもないため受け付けない。
const 上限のテクセル数: u16 = 4096;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 影の一辺解像度(u16);

impl 影の一辺解像度 {
    pub fn 生成する(テクセル数: u32) -> Result<Self, ライティング入力エラー> {
        let 収まる値 = u16::try_from(テクセル数).map_err(|_| ライティング入力エラー::影の一辺解像度不正)?;
        if !収まる値.is_power_of_two() || !(下限のテクセル数..=上限のテクセル数).contains(&収まる値) {
            return Err(ライティング入力エラー::影の一辺解像度不正);
        }
        Ok(Self(収まる値))
    }

    pub fn 既定() -> Self {
        Self(既定のテクセル数)
    }

    /// シャドウマップ資源の寸法とグラフの登録が読む一辺のテクセル数。
    pub fn テクセル数(self) -> u32 {
        u32::from(self.0)
    }

    /// ビューポート・シザーとスナップの刻みが読む実数のテクセル数。u16に収まる不変条件があるため変換が失敗しない。
    pub(crate) fn 実数のテクセル数(self) -> f32 {
        f32::from(self.0)
    }

    /// 1テクセルが占める正規化座標の幅。2の冪であるためこの逆数はf32で誤差なく表せる。
    pub(crate) fn テクセル尺度(self) -> f32 {
        1.0 / self.実数のテクセル数()
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn 既定は二千四十八であり本番の品質要件と一致する() {
        assert_eq!(影の一辺解像度::既定().テクセル数(), 2048);
        assert_eq!(影の一辺解像度::既定(), 影の一辺解像度::生成する(2048).unwrap());
    }

    #[test]
    fn 計測で振る三つの値を受け付ける() {
        for テクセル数 in [1024, 2048, 4096] {
            assert_eq!(影の一辺解像度::生成する(テクセル数).unwrap().テクセル数(), テクセル数);
        }
    }

    #[test]
    fn 二の冪でない値と範囲外の値を拒む() {
        for テクセル数 in [0, 1000, 3000, 128, 8192, 16384, 70000] {
            assert_eq!(影の一辺解像度::生成する(テクセル数), Err(ライティング入力エラー::影の一辺解像度不正));
        }
    }

    #[test]
    fn テクセル尺度は逆数であり誤差を持たない() {
        assert_eq!(影の一辺解像度::生成する(1024).unwrap().テクセル尺度(), 1.0 / 1024.0);
        assert_eq!(影の一辺解像度::既定().テクセル尺度(), 0.000_488_281_25);
    }
}
