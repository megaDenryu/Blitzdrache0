//! カスケードの距離区分の識別子と、距離区分が受け持つビュー空間深度の区間。
//! 距離区分を`usize`で持ち回ると、範囲外の添字と「4距離区分である」という前提が呼び出し側に散るため、列挙で表す。

use blitz_math::メートル;

use super::距離区分数;

/// カメラからの距離区分。番号が大きいほどカメラから遠い。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 距離区分番号 {
    距離区分0,
    距離区分1,
    距離区分2,
    距離区分3,
}

impl 距離区分番号 {
    /// カメラに近い順の全距離区分。シャドウ記録も資源の生成もこの順で回す。
    pub fn 全距離区分() -> [Self; 距離区分数] {
        [Self::距離区分0, Self::距離区分1, Self::距離区分2, Self::距離区分3]
    }

    pub fn 添字(self) -> usize {
        match self {
            Self::距離区分0 => 0,
            Self::距離区分1 => 1,
            Self::距離区分2 => 2,
            Self::距離区分3 => 3,
        }
    }

    /// この距離区分のシャドウ記録がレンダーグラフへ積むパスの名前。GPU計測はパス名で移動平均を参照するため、
    /// 距離区分を跨いだ合算にせず距離区分ごとに固定の文字列を持つ。合計を出す側もこの名前で参照する。
    pub fn シャドウパス名(self) -> &'static str {
        match self {
            Self::距離区分0 => "シャドウ距離区分0",
            Self::距離区分1 => "シャドウ距離区分1",
            Self::距離区分2 => "シャドウ距離区分2",
            Self::距離区分3 => "シャドウ距離区分3",
        }
    }

    pub(crate) fn 次の距離区分(self) -> Self {
        match self {
            Self::距離区分0 => Self::距離区分1,
            Self::距離区分1 => Self::距離区分2,
            Self::距離区分2 | Self::距離区分3 => Self::距離区分3,
        }
    }
}

/// 1つの距離区分が受け持つカメラ視錐台のスライス。深度はカメラ前方向に沿ったビュー空間の距離である。
/// 隣の距離区分との重なりぶんだけ近側へ伸びており、`近深度`は1つ手前の距離区分の`遠深度`より小さい。
#[derive(Debug, Clone, Copy)]
pub struct 距離区分の区間 {
    近深度: メートル,
    遠深度: メートル,
}

impl 距離区分の区間 {
    pub(super) fn 生成する(近深度: メートル, 遠深度: メートル) -> Self {
        Self { 近深度, 遠深度 }
    }

    pub fn 近深度(self) -> メートル {
        self.近深度
    }

    pub fn 遠深度(self) -> メートル {
        self.遠深度
    }
}
