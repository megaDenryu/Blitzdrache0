//! カスケードの分割と正射影の形を決める設定値。定数で契約化せず型付きの設定にするのは、
//! 検収シーンの世界メートル毎テクセルを見て確定する値だからである
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「カスケードシャドウ(CSM)」)。

use blitz_math::メートル;

use crate::lighting_input::ライティング入力エラー;

/// 一様分割と対数分割の混ぜ方。0で一様分割、1で対数分割になる。
#[derive(Debug, Clone, Copy)]
pub struct 実用分割混合率(f32);

impl 実用分割混合率 {
    pub fn 生成する(値: f32) -> Result<Self, ライティング入力エラー> {
        if !値.is_finite() || !(0.0..=1.0).contains(&値) {
            return Err(ライティング入力エラー::混合率不正);
        }
        Ok(Self(値))
    }

    pub(super) fn 値(self) -> f32 {
        self.0
    }
}

/// 隣り合う帯が重なる割合。手前の帯の深度幅に対する比で表し、その幅ぶん次の帯が近側へ伸びる。
#[derive(Debug, Clone, Copy)]
pub struct 帯重なり率(f32);

impl 帯重なり率 {
    pub fn 生成する(値: f32) -> Result<Self, ライティング入力エラー> {
        if !値.is_finite() || !(0.05..=0.10).contains(&値) {
            return Err(ライティング入力エラー::重なり率不正);
        }
        Ok(Self(値))
    }

    pub(super) fn 値(self) -> f32 {
        self.0
    }
}

#[derive(Debug, Clone, Copy)]
pub struct カスケード設定 {
    最大影距離: メートル,
    混合率: 実用分割混合率,
    重なり率: 帯重なり率,
    キャスター余白: メートル,
}

impl カスケード設定 {
    pub fn 生成する(
        最大影距離: メートル,
        混合率: 実用分割混合率,
        重なり率: 帯重なり率,
        キャスター余白: メートル,
    ) -> Result<Self, ライティング入力エラー> {
        if !最大影距離.値().is_finite() || 最大影距離.値() <= 0.0 {
            return Err(ライティング入力エラー::最大影距離不正);
        }
        if !キャスター余白.値().is_finite() || キャスター余白.値() < 0.0 {
            return Err(ライティング入力エラー::キャスター余白不正);
        }
        Ok(Self {
            最大影距離,
            混合率,
            重なり率,
            キャスター余白,
        })
    }

    /// 既定値。最大影距離300メートルは、検証用地形世界(一辺100メートルのチャンクが5×5)を距離150メートルから
    /// 見下ろす検収構図で、4帯すべてに地形と植生が入る最小の桁である。混合率0.6は設計正本の初期値である。
    pub fn 既定() -> Self {
        Self {
            最大影距離: メートル::生成する(300.0),
            混合率: 実用分割混合率(0.6),
            重なり率: 帯重なり率(0.07),
            キャスター余白: メートル::生成する(60.0),
        }
    }

    pub(super) fn 最大影距離(self) -> メートル {
        self.最大影距離
    }

    pub(super) fn 混合率(self) -> 実用分割混合率 {
        self.混合率
    }

    pub(super) fn 重なり率(self) -> 帯重なり率 {
        self.重なり率
    }

    pub(super) fn キャスター余白(self) -> メートル {
        self.キャスター余白
    }
}
