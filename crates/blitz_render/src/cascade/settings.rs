//! 多段の分割と正射影の形を決める設定値。定数で契約化せず型付きの設定にするのは、
//! 検収シーンの世界メートル毎テクセルを見て確定する値だからである
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「多段シャドウ(CSM)」)。

use blitz_math::メートル;

use super::ratio::{実用分割混合率, 距離区分の重なり率};
use super::resolution::影の一辺解像度;
use crate::lighting_input::ライティング入力エラー;

#[derive(Debug, Clone, Copy)]
pub struct 多段設定 {
    最大影距離: メートル,
    混合率: 実用分割混合率,
    重なり率: 距離区分の重なり率,
    キャスター余白: メートル,
    解像度: 影の一辺解像度,
}

impl 多段設定 {
    pub fn 生成する(
        最大影距離: メートル,
        混合率: 実用分割混合率,
        重なり率: 距離区分の重なり率,
        キャスター余白: メートル,
        解像度: 影の一辺解像度,
    ) -> Result<Self, ライティング入力エラー> {
        if !最大影距離.値().is_finite() || 最大影距離.値() <= 0.0 {
            return Err(ライティング入力エラー::最大影距離不正);
        }
        if !キャスター余白.値().is_finite() || キャスター余白.値() < 0.0 {
            return Err(ライティング入力エラー::キャスター余白不正);
        }
        Ok(Self {
            最大影距離,
            混合率,
            重なり率,
            キャスター余白,
            解像度,
        })
    }

    /// 既定値。最大影距離300メートルは、検証用地形世界(一辺100メートルのチャンクが5×5)を距離150メートルから
    /// 見下ろす検収構図で、4距離区分すべてに地形と植生が入る最小の桁である。混合率0.6は設計正本の初期値である。
    pub fn 既定() -> Self {
        Self {
            最大影距離: メートル::生成する(300.0),
            混合率: 実用分割混合率::既定(),
            重なり率: 距離区分の重なり率::既定(),
            キャスター余白: メートル::生成する(60.0),
            解像度: 影の一辺解像度::既定(),
        }
    }

    /// 最大影距離だけを差し替えた設定を返す。分割の混ぜ方と余白は世界に依らず同じでよく、
    /// 「どこまで影を出すか」だけが世界の広さで変わるためである。
    pub fn 最大影距離を差し替える(self, 最大影距離: メートル) -> Result<Self, ライティング入力エラー> {
        Self::生成する(最大影距離, self.混合率, self.重なり率, self.キャスター余白, self.解像度)
    }

    /// キャスター余白だけを差し替えた設定を返す。余白は正射影のZ範囲へ入って距離区分の光空間直方体の
    /// 区間を延ばすため、律速切り分けの計測でこの1軸だけを振る。
    pub fn キャスター余白を差し替える(self, キャスター余白: メートル) -> Result<Self, ライティング入力エラー> {
        Self::生成する(self.最大影距離, self.混合率, self.重なり率, キャスター余白, self.解像度)
    }

    /// シャドウマップの一辺だけを差し替えた設定を返す。テクセルスナップの刻みと正射影の半幅の余裕が
    /// この値から決まるため、シャドウマップ資源の一辺と食い違ってはならない(食い違いはレンダラーが検出する)。
    pub fn 解像度を差し替える(self, 解像度: 影の一辺解像度) -> Self {
        Self { 解像度, ..self }
    }

    pub(super) fn 最大影距離(self) -> メートル {
        self.最大影距離
    }

    pub(super) fn 混合率(self) -> 実用分割混合率 {
        self.混合率
    }

    pub(super) fn 重なり率(self) -> 距離区分の重なり率 {
        self.重なり率
    }

    pub(super) fn キャスター余白(self) -> メートル {
        self.キャスター余白
    }

    pub fn 解像度(self) -> 影の一辺解像度 {
        self.解像度
    }
}
