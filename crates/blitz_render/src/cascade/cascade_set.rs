//! 1フレームぶんの多段の構築結果。シェーダー定数書込・距離区分別のシャドウ記録・距離区分別のシャドウ候補の可視判定が
//! すべてこの1つの値を読むことで、判定に使った範囲と実際に描く範囲がずれないようにする(単一正本の契約)。
//! 距離区分別の可視個体の選別(第6段)では、可視判定が距離区分ごとに`距離区分のライトビュー射影`を呼んで4つの視錐台を導く。
//! 全距離区分を1つの正射影で覆う包囲は第5段の暫定であり、距離区分別の判定が本番接続された時点で呼び出し元が無くなったため削除した。

use blitz_math::{メートル, ワールド, 位置, 光源クリップ, 変換, 大域ワールド位置, 座標変換エラー};

use super::band::{距離区分の区間, 距離区分番号};
use super::texel_density::影の解像度密度;
use super::{距離区分の境界数, 距離区分数};
use crate::lighting_input::{影入力, 方向光入力};

pub struct 多段一式 {
    pub(super) 方向光: 方向光入力,
    pub(super) 距離区分一覧: [影入力; 距離区分数],
    pub(super) 区間一覧: [距離区分の区間; 距離区分数],
    pub(super) 分割深度: [メートル; 距離区分の境界数],
    pub(super) 遷移幅: [メートル; 距離区分の境界数],
    /// 距離区分ごとのスライスの8隅(カメラ相対フレーム)。行列と同じ構築結果から取るため、
    /// 隅を使う検査や後段の距離区分別の判定が行列とずれた幾何を見ることはない。
    pub(super) 隅一覧: [[位置<ワールド>; 8]; 距離区分数],
    /// テクセルスナップの刻みと同じ値である。刻みは正射影の全幅をテクセル数で割った長さそのものだからである。
    pub(super) 解像度密度: 影の解像度密度,
    pub(super) カメラ前方: [f32; 3],
}

impl 多段一式 {
    /// 距離区分ごとのライトビュー射影を、与えた原点の相対フレームで組み立てる。
    /// 注意: 呼び出し元は対象の座標と同じカメラ大域原点を渡す責務を負う。
    pub fn 距離区分のライトビュー射影(
        &self,
        番号: 距離区分番号,
        相対フレーム原点: 大域ワールド位置,
    ) -> Result<変換<ワールド, 光源クリップ>, 座標変換エラー> {
        self.距離区分一覧[番号.添字()].ライトビュー射影を組み立てる(self.方向光, 相対フレーム原点)
    }

    pub fn 区間(&self, 番号: 距離区分番号) -> 距離区分の区間 {
        self.区間一覧[番号.添字()]
    }

    pub fn 分割深度(&self) -> [メートル; 距離区分の境界数] {
        self.分割深度
    }

    pub fn 遷移幅(&self) -> [メートル; 距離区分の境界数] {
        self.遷移幅
    }

    /// その距離区分が受け持つカメラ視錐台スライスの8隅(カメラ相対フレーム)。
    pub fn 隅一覧(&self, 番号: 距離区分番号) -> [位置<ワールド>; 8] {
        self.隅一覧[番号.添字()]
    }

    /// 距離区分ごとの、シャドウマップの1テクセルが世界で覆う長さ。予算との突き合わせがこれを読む。
    pub fn 解像度密度(&self) -> 影の解像度密度 {
        self.解像度密度
    }

    /// GPU境界向けのカメラ前方向(カメラ相対フレームの単位ベクトル)。
    /// シーンの画素段はこの向きとの内積でビュー空間深度を求め、距離区分を選ぶ。
    pub fn カメラ前方(&self) -> [f32; 3] {
        self.カメラ前方
    }
}
