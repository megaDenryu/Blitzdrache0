//! 1フレームぶんのカスケードの構築結果。ユニフォーム書込・帯別のシャドウ記録・シャドウ候補の可視判定が
//! すべてこの1つの値を読むことで、判定に使った範囲と実際に描く範囲がずれないようにする(単一正本の契約)。

use blitz_math::{メートル, ワールド, 位置, 光源クリップ, 変換, 大域ワールド位置, 座標変換エラー};

use super::band::{帯区間, 帯番号};
use super::{帯境界数, 帯数};
use crate::lighting_input::{影入力, 方向光入力};

pub struct カスケード一式 {
    pub(super) 方向光: 方向光入力,
    pub(super) 帯一覧: [影入力; 帯数],
    pub(super) 区間一覧: [帯区間; 帯数],
    pub(super) 分割深度: [メートル; 帯境界数],
    pub(super) 遷移幅: [メートル; 帯境界数],
    /// 帯ごとのスライスの8隅(カメラ相対フレーム)。行列と同じ構築結果から取るため、
    /// 隅を使う検査や後段の帯別判定が行列とずれた幾何を見ることはない。
    pub(super) 隅一覧: [[位置<ワールド>; 8]; 帯数],
    pub(super) カメラ前方: [f32; 3],
    pub(super) 包囲: 影入力,
}

impl カスケード一式 {
    /// 帯ごとのライトビュー射影を、与えた原点の相対フレームで組み立てる。
    /// 注意: 呼び出し元は対象の座標と同じカメラ大域原点を渡す責務を負う。
    pub fn 帯のライトビュー射影(
        &self,
        番号: 帯番号,
        相対フレーム原点: 大域ワールド位置,
    ) -> Result<変換<ワールド, 光源クリップ>, 座標変換エラー> {
        self.帯一覧[番号.添字()].ライトビュー射影を組み立てる(self.方向光, 相対フレーム原点)
    }

    /// 全帯を覆う1つの正射影。この段のシャドウ候補の可視判定は、帯別に絞らずこの範囲で保守的に行う
    /// (帯別カリングは第6段。参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「段階導入」)。
    pub fn 包囲影入力(&self) -> 影入力 {
        self.包囲
    }

    pub fn 区間(&self, 番号: 帯番号) -> 帯区間 {
        self.区間一覧[番号.添字()]
    }

    pub fn 分割深度(&self) -> [メートル; 帯境界数] {
        self.分割深度
    }

    pub fn 遷移幅(&self) -> [メートル; 帯境界数] {
        self.遷移幅
    }

    /// その帯が受け持つカメラ視錐台スライスの8隅(カメラ相対フレーム)。
    pub fn 隅一覧(&self, 番号: 帯番号) -> [位置<ワールド>; 8] {
        self.隅一覧[番号.添字()]
    }

    /// GPU境界向けのカメラ前方向(カメラ相対フレームの単位ベクトル)。
    /// シーンのフラグメントはこの向きとの内積でビュー空間深度を求め、帯を選ぶ。
    pub fn カメラ前方(&self) -> [f32; 3] {
        self.カメラ前方
    }
}
