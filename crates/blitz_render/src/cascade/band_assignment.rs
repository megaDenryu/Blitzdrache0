//! 距離区分をどこまで・どう割り当てるかの2値。受け取るのは最大影距離と分け方、返すのは検証済みの割り当てである。
//!
//! この2つを1つの型が持つのは、両者の間に「最も遠い境界は最大影距離より手前」という不変条件があるためである。
//! 別々のフィールドとして多段設定へ並べると、片方だけを差し替える一手で不変条件の破れた設定が作れてしまう。
//!
//! 多段設定の他の値(重なり率・キャスター余白・解像度)と分けるのは、設計正本が「最大影距離は世界ごとの方針」
//! 「分割の混ぜ方・重なり・キャスター余白は世界に依らない」と定めており、世界ごとに動く軸がこの2つだけだからである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「最大影距離は世界ごとの方針である」

use blitz_math::メートル;

use super::explicit_boundaries::明示の距離区分境界;
use super::ratio::実用分割混合率;
use super::split_policy::距離区分の分け方;
use crate::lighting_input::ライティング入力エラー;

/// 不変条件: 最大影距離は有限かつ正であり、明示の境界を選んだときは最も遠い境界が最大影距離より手前にある。
#[derive(Debug, Clone, Copy)]
pub struct 距離区分の割り当て {
    最大影距離: メートル,
    分け方: 距離区分の分け方,
}

impl 距離区分の割り当て {
    pub fn 生成する(最大影距離: メートル, 分け方: 距離区分の分け方) -> Result<Self, ライティング入力エラー> {
        if !最大影距離.値().is_finite() || 最大影距離.値() <= 0.0 {
            return Err(ライティング入力エラー::最大影距離不正);
        }
        if let 距離区分の分け方::明示の境界(境界) = 分け方 {
            // 境界が最大影距離を超えると最奥の距離区分の区間が反転し、包囲球の半径が負になる。
            if 境界.最も遠い境界().値() >= 最大影距離.値() {
                return Err(ライティング入力エラー::明示の距離区分境界が最大影距離を超えた);
            }
        }
        Ok(Self { 最大影距離, 分け方 })
    }

    /// 既定の225メートルと実用分割。世界の構造と距離区分の担当を対応させる必要が無い世界がこれを受ける。
    pub(super) fn 既定() -> Self {
        Self {
            最大影距離: メートル::生成する(225.0),
            分け方: 距離区分の分け方::実用分割(実用分割混合率::既定()),
        }
    }

    /// 最大影距離だけを差し替える。実用分割は境界を最大影距離から作り直すため不変条件は自動で保たれ、
    /// 明示の境界を選んでいる設定へこれを当てると境界との関係を生成が改めて検査する。
    pub fn 最大影距離を差し替える(self, 最大影距離: メートル) -> Result<Self, ライティング入力エラー> {
        Self::生成する(最大影距離, self.分け方)
    }

    /// 境界の並びと最大影距離を同時に決める。2つを別々に差し替えられるようにすると、途中の一手で
    /// 不変条件の破れた割り当てが作れてしまうため、明示の境界へ移る操作は1回の呼び出しで両方を決める。
    pub fn 明示の境界で分ける(
        境界: 明示の距離区分境界, 最大影距離: メートル
    ) -> Result<Self, ライティング入力エラー> {
        Self::生成する(最大影距離, 距離区分の分け方::明示の境界(境界))
    }

    pub fn 最大影距離(self) -> メートル {
        self.最大影距離
    }

    pub fn 分け方(self) -> 距離区分の分け方 {
        self.分け方
    }
}
