//! ビュー空間深度から、その画素が引く2つの距離区分とその重みを決める工程。
//! この関数が距離区分の選択と境界ブレンドの正本であり、`shaders/cascade_shadow.slang`の`selectCascadeBlend`は同じ式の写しである。
//! Rust側に置くのは、重みが単調で和が1であることをユニットテストで検査できるようにするためである。

use blitz_math::メートル;

use super::band::距離区分番号;
use super::距離区分の境界数;

/// 2つの距離区分とその重み。`副距離区分`は`主距離区分`と同じこともあり、そのとき`主重み`は1になる。
/// 重みは和が1になるため、副距離区分の重みは`1 - 主重み`である。
#[derive(Debug, Clone, Copy)]
pub struct 距離区分のブレンド {
    pub 主距離区分: 距離区分番号,
    pub 副距離区分: 距離区分番号,
    pub 主重み: f32,
}

/// 深度が境界の手前の遷移幅に入っているとき、その距離区分と次の距離区分を線形に混ぜる。
/// 遷移域を境界の手前側に置くのは、距離区分の区間が次の距離区分の側へ重なりぶん伸びているためである
/// (参照: `crates/blitz_render/src/cascade/split.rs`)。
pub fn 距離区分を選ぶ(
    ビュー深度: メートル,
    分割深度: [メートル; 距離区分の境界数],
    遷移幅: [メートル; 距離区分の境界数],
) -> 距離区分のブレンド {
    let 深度 = ビュー深度.値();
    for (添字, 距離区分) in [距離区分番号::距離区分0, 距離区分番号::距離区分1, 距離区分番号::距離区分2]
        .into_iter()
        .enumerate()
    {
        let 境界 = 分割深度[添字].値();
        if 深度 > 境界 {
            continue;
        }
        let 幅 = 遷移幅[添字].値();
        let 遷移開始 = 境界 - 幅;
        if 幅 > 0.0 && 深度 >= 遷移開始 {
            let 進み = ((深度 - 遷移開始) / 幅).clamp(0.0, 1.0);
            return 距離区分のブレンド {
                主距離区分: 距離区分,
                副距離区分: 距離区分.次の距離区分(),
                主重み: 1.0 - 進み,
            };
        }
        return 距離区分のブレンド {
            主距離区分: 距離区分,
            副距離区分: 距離区分,
            主重み: 1.0,
        };
    }
    距離区分のブレンド {
        主距離区分: 距離区分番号::距離区分3,
        副距離区分: 距離区分番号::距離区分3,
        主重み: 1.0,
    }
}
