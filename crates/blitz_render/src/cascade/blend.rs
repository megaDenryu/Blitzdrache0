//! ビュー空間深度から、その画素が引く2つの帯とその重みを決める工程。
//! この関数が帯選択と境界ブレンドの正本であり、`shaders/lighting.slang`の`selectCascadeBlend`は同じ式の写しである。
//! Rust側に置くのは、重みが単調で和が1であることをユニットテストで検査できるようにするためである。

use blitz_math::メートル;

use super::band::帯番号;
use super::帯境界数;

/// 2つの帯とその重み。`副帯`は`主帯`と同じこともあり、そのとき`主重み`は1になる。
/// 重みは和が1になるため、副帯の重みは`1 - 主重み`である。
#[derive(Debug, Clone, Copy)]
pub struct 帯ブレンド {
    pub 主帯: 帯番号,
    pub 副帯: 帯番号,
    pub 主重み: f32,
}

/// 深度が境界の手前の遷移幅に入っているとき、その帯と次の帯を線形に混ぜる。
/// 遷移帯を境界の手前側に置くのは、帯区間が次の帯の側へ重なりぶん伸びているためである
/// (参照: `crates/blitz_render/src/cascade/split.rs`)。
pub fn 帯を選ぶ(
    ビュー深度: メートル, 分割深度: [メートル; 帯境界数], 遷移幅: [メートル; 帯境界数]
) -> 帯ブレンド {
    let 深度 = ビュー深度.値();
    for (添字, 帯) in [帯番号::帯0, 帯番号::帯1, 帯番号::帯2].into_iter().enumerate() {
        let 境界 = 分割深度[添字].値();
        if 深度 > 境界 {
            continue;
        }
        let 幅 = 遷移幅[添字].値();
        let 遷移開始 = 境界 - 幅;
        if 幅 > 0.0 && 深度 >= 遷移開始 {
            let 進み = ((深度 - 遷移開始) / 幅).clamp(0.0, 1.0);
            return 帯ブレンド {
                主帯: 帯,
                副帯: 帯.次の帯(),
                主重み: 1.0 - 進み,
            };
        }
        return 帯ブレンド {
            主帯: 帯,
            副帯: 帯,
            主重み: 1.0,
        };
    }
    帯ブレンド {
        主帯: 帯番号::帯3,
        副帯: 帯番号::帯3,
        主重み: 1.0,
    }
}
