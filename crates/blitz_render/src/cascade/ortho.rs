//! 距離区分の包囲球から正射影の再構築パラメータを組み立てる工程。
//! 受け取るのは正射影の中心の大域位置と3軸の半幅、返すのは既存の`影入力`である。
//!
//! 距離区分ごとの正射影を専用の型でなく`影入力`で持つのは、カメラ大域原点を引いてライトビュー射影を作る
//! 単一の組立メソッドをそのまま使うためである。距離区分が増えても相対フレームの契約が1箇所に留まる。

use blitz_math::{メートル, 大域ワールド位置};

use crate::lighting_input::{ライティング入力エラー, 影入力, 影正射影範囲};

/// 正射影の近クリップ。0にできない(範囲の検証が正を要求する)ため、世界の寸法に対して無視できる値を置く。
const 近クリップ: f32 = 0.1;

/// 中心と3軸の半幅から影の再構築パラメータを作る。光源は中心から光の逆向きへ「奥行き半幅 + キャスター余白 + 近クリップ」
/// だけ離す。この距離の取り方により、距離区分の外にあるキャスターも余白ぶんだけ正射影の中に入る。
pub(super) fn 正射影を作る(
    中心: 大域ワールド位置,
    横半幅: メートル,
    縦半幅: メートル,
    奥行き半幅: メートル,
    キャスター余白: メートル,
) -> Result<影入力, ライティング入力エラー> {
    let 近 = メートル::生成する(近クリップ);
    let 光源距離 = 奥行き半幅 + キャスター余白 + 近;
    let 遠 = 光源距離 + 奥行き半幅;
    let 範囲 = 影正射影範囲::生成する(横半幅, 縦半幅, 近, 遠)?;
    影入力::生成する(中心, 光源距離, 範囲)
}
