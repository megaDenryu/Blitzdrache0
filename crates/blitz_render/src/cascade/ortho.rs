//! 光空間の基底と、帯の包囲から正射影の再構築パラメータを組み立てる工程。
//! 受け取るのは正射影の中心の大域位置と3軸の半幅、返すのは既存の`影入力`である。
//!
//! 帯ごとの正射影を専用の型でなく`影入力`で持つのは、カメラ大域原点を引いてライトビュー射影を作る
//! 単一の組立メソッドをそのまま使うためである。帯が増えても相対フレームの契約が1箇所に留まる。

use blitz_math::{ビュー, メートル, ワールド, 位置, 変換, 大域ワールド位置};

use crate::lighting_input::{ライティング入力エラー, 影入力, 影正射影範囲, 方向光入力};

/// 正射影の近クリップ。0にできない(範囲の検証が正を要求する)ため、世界の寸法に対して無視できる値を置く。
const 近クリップ: f32 = 0.1;

/// 光の向きだけを持つ基底(視点は原点)。帯どうしの包囲を同じ座標で比べるために使う。
/// 前提: `変換::注視`と同じ上方向の規約に従うため、光がほぼ真上・真下のときは基底が退化する。
pub(super) fn 光基底(方向光: 方向光入力) -> 変換<ワールド, ビュー> {
    let 向き = 方向光.方向();
    let 原点: 位置<ワールド> = 位置::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0));
    let 注視点: 位置<ワールド> = 位置::生成する(メートル::生成する(向き[0]), メートル::生成する(向き[1]), メートル::生成する(向き[2]));
    変換::注視(原点, 注視点)
}

/// 中心と3軸の半幅から影の再構築パラメータを作る。光源は中心から光の逆向きへ「奥行き半幅 + キャスター余白 + 近クリップ」
/// だけ離す。この距離の取り方により、帯の外にあるキャスターも余白ぶんだけ正射影の中に入る。
pub(super) fn 正射影を作る(
    中心: 大域ワールド位置,
    横半幅: メートル,
    縦半幅: メートル,
    奥行き半幅: メートル,
    キャスター余白: メートル,
) -> Result<影入力, ライティング入力エラー> {
    let 近 = メートル::生成する(近クリップ);
    let 光源距離 = 奥行き半幅 + キャスター余白 + 近;
    let 遠 = 光源距離 + 奥行き半幅;
    let 範囲 = 影正射影範囲::生成する(横半幅, 縦半幅, 近, 遠)?;
    影入力::生成する(中心, 光源距離, 範囲)
}
