//! 設計が距離で名指しした距離区分の境界。受け取るのは境界の距離の並び、返すのは検証済みの境界である。
//!
//! 実用分割は近深度と最大影距離だけから境界を計算するため、世界の構造と距離区分の担当を対応させられない。
//! 大規模世界のように「接地・1チャンク・先読み層・遠景層」と距離区分が1対1で対応する世界は、計算でなく
//! 名指しで境界を置く。最大影距離だけを10000メートルへ替えて実用分割に任せると境界が約1001・2019・3337
//! メートルになり、近景の3区分をまとめて失う。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「多段シャドウの4距離区分の再配分は、遠景の段で行う」

use blitz_math::メートル;

use super::距離区分の境界数;
use crate::lighting_input::ライティング入力エラー;

/// 距離区分の境界をカメラに近い順で並べたもの。
///
/// 不変条件: すべて有限かつ正であり、近い順に狭義単調増加である。等しい隣り合いを許さないのは、
/// 幅0の距離区分がシャドウマップを1枚まるごと無駄にし、遷移域の重みも定義できなくなるためである。
#[derive(Debug, Clone, Copy)]
pub struct 明示の距離区分境界([メートル; 距離区分の境界数]);

impl 明示の距離区分境界 {
    pub fn 生成する(境界: [メートル; 距離区分の境界数]) -> Result<Self, ライティング入力エラー> {
        let mut 手前 = 0.0;
        for 距離 in 境界 {
            if !距離.値().is_finite() || 距離.値() <= 手前 {
                return Err(ライティング入力エラー::明示の距離区分境界不正);
            }
            手前 = 距離.値();
        }
        Ok(Self(境界))
    }

    pub fn 距離一覧(self) -> [メートル; 距離区分の境界数] {
        self.0
    }

    /// 最も遠い境界。多段設定が「境界が最大影距離より手前にあること」を検査するために読む。
    pub(super) fn 最も遠い境界(self) -> メートル {
        self.0[距離区分の境界数 - 1]
    }
}
