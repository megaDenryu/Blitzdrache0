//! 実用分割(一様分割と対数分割の混合)で分割深度を求め、重なりぶんだけ近側へ伸ばした距離区分の区間を作る工程。
//! 受け取るのはカメラ視錐台の近深度・最大影距離・設定であり、返すのは分割深度と距離区分の区間と遷移幅である。

use blitz_math::メートル;

use super::band::距離区分の区間;
use super::settings::多段設定;
use super::{距離区分の境界数, 距離区分数};

/// 分割深度・距離区分の区間・遷移幅の3つは同じ計算から一度に出るため、1つの値として返す。
pub(super) struct 分割結果 {
    pub(super) 分割深度: [メートル; 距離区分の境界数],
    pub(super) 遷移幅: [メートル; 距離区分の境界数],
    pub(super) 距離区分の区間一覧: [距離区分の区間; 距離区分数],
}

/// 分割深度 d_i = 混合率 × 対数分割 + (1 - 混合率) × 一様分割 (i = 1..距離区分数-1)。
/// 対数分割は近深度が0に近いほど手前へ寄るため、実用分割は一様分割との混合でその偏りを緩める。
pub(super) fn 分割する(近深度: メートル, 遠深度: メートル, 設定: 多段設定) -> 分割結果 {
    let 近 = 近深度.値();
    let 遠 = 遠深度.値();
    let 混合率 = 設定.混合率().値();
    let 距離区分数f = f32::from(u8::try_from(距離区分数).unwrap_or(4));
    let mut 分割深度 = [メートル::生成する(0.0); 距離区分の境界数];
    for (添字, 保存先) in 分割深度.iter_mut().enumerate() {
        let 割合 = (f32::from(u8::try_from(添字 + 1).unwrap_or(1))) / 距離区分数f;
        let 対数 = 近 * (遠 / 近).powf(割合);
        let 一様 = 近 + (遠 - 近) * 割合;
        *保存先 = メートル::生成する(混合率 * 対数 + (1.0 - 混合率) * 一様);
    }

    let 重なり率 = 設定.重なり率().値();
    let mut 遷移幅 = [メートル::生成する(0.0); 距離区分の境界数];
    let mut 区間近側 = [メートル::生成する(0.0); 距離区分数];
    区間近側[0] = 近深度;
    for 添字 in 0..距離区分の境界数 {
        let 遠側 = 分割深度[添字];
        let 幅 = (遠側 - 区間近側[添字]) * 重なり率;
        遷移幅[添字] = 幅;
        区間近側[添字 + 1] = 遠側 - 幅;
    }

    let 距離区分の区間一覧 = std::array::from_fn(|添字| {
        let 遠側 = if 添字 == 距離区分の境界数 {
            遠深度
        } else {
            分割深度[添字]
        };
        距離区分の区間::生成する(区間近側[添字], 遠側)
    });
    分割結果 {
        分割深度,
        遷移幅,
        距離区分の区間一覧,
    }
}
