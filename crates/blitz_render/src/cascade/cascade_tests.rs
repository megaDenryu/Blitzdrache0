//! CSM数学の検証(設計正本「検証の設計」層2)の共通の器。検査そのものは2つの子モジュールが持ち、
//! ここには全検査が使う入力(方向光・カメラ相対ビュー射影・大域位置)の組み立てだけを置く。

#![allow(clippy::unwrap_used)]

mod ortho_tests;
mod snap_tests;
mod split_tests;

use blitz_math::{クリップ, ビュー, メートル, ラジアン, ワールド, 位置, 変換, 大域メートル, 大域ワールド位置};

use crate::lighting_input::{光強度, 光色, 方向光入力};

fn m(値: f32) -> メートル {
    メートル::生成する(値)
}

fn 大域(x: f64, y: f64, z: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(x), 大域メートル::生成する(y), 大域メートル::生成する(z))
}

fn 方向光() -> 方向光入力 {
    方向光入力::生成する(-0.4, -1.0, -0.6, 光色::生成する(1.0, 1.0, 1.0).unwrap(), 光強度::生成する(3.0).unwrap()).unwrap()
}

/// カメラ相対フレームのビュー射影(視点は原点、回転だけを持つ)。
fn ビュー射影() -> 変換<ワールド, クリップ> {
    let 原点: 位置<ワールド> = 位置::生成する(m(0.0), m(0.0), m(0.0));
    let 注視点: 位置<ワールド> = 位置::生成する(m(0.3), m(-0.5), m(-1.0));
    let ビュー変換: 変換<ワールド, ビュー> = 変換::注視(原点, 注視点);
    let 投影: 変換<ビュー, クリップ> = 変換::透視投影(ラジアン::度から(60.0), 16.0 / 9.0, m(0.1), m(1000.0));
    ビュー変換.合成する(投影)
}
