//! 全帯を1つの正射影で覆う包囲を求める工程。受け取るのは帯ごとの中心と半幅、返すのは包囲の`影入力`である。
//! シャドウ候補の可視判定はこの1つの範囲で行う。帯ごとに視錐台を4つ持って和を取る形にしないのは、
//! この段の判定が保守的でよく、判定側の型と経路を4本に増やす理由が無いためである。

use blitz_math::{ビュー, メートル, ワールド, 位置, 大域メートル, 大域ワールド位置};

use super::build::帯の包囲;
use super::ortho;
use crate::lighting_input::{ライティング入力エラー, 影入力, 方向光入力};

pub(super) fn 包囲を求める(
    方向光: 方向光入力,
    カメラ大域原点: 大域ワールド位置,
    帯一覧: &[帯の包囲],
    キャスター余白: メートル,
) -> Result<影入力, ライティング入力エラー> {
    let 基底 = ortho::光基底(方向光);
    let mut 最小 = [f32::MAX; 3];
    let mut 最大 = [f32::MIN; 3];
    for 帯 in 帯一覧 {
        let 相対 = 帯
            .中心
            .カメラ相対へ変換する(カメラ大域原点)
            .map_err(|_| ライティング入力エラー::カスケード視錐台不正)?;
        let 光空間: 位置<ビュー> = 基底.適用する(位置::<ワールド>::生成する(相対.x(), 相対.y(), 相対.z()));
        let 中心 = [光空間.x().値(), 光空間.y().値(), 光空間.z().値()];
        let 半幅 = [帯.横縦半幅.値(), 帯.横縦半幅.値(), 帯.奥行き半幅.値()];
        for 軸 in 0..3 {
            最小[軸] = 最小[軸].min(中心[軸] - 半幅[軸]);
            最大[軸] = 最大[軸].max(中心[軸] + 半幅[軸]);
        }
    }

    let 中心光空間: 位置<ビュー> = 位置::生成する(
        メートル::生成する((最小[0] + 最大[0]) * 0.5),
        メートル::生成する((最小[1] + 最大[1]) * 0.5),
        メートル::生成する((最小[2] + 最大[2]) * 0.5),
    );
    let 中心相対: 位置<ワールド> = 基底.逆変換する().適用する(中心光空間);
    let 中心 = カメラ大域原点.平行移動する(大域ワールド位置::生成する(
        大域メートル::生成する(f64::from(中心相対.x().値())),
        大域メートル::生成する(f64::from(中心相対.y().値())),
        大域メートル::生成する(f64::from(中心相対.z().値())),
    ));
    let 半幅 = |軸: usize| メートル::生成する((最大[軸] - 最小[軸]) * 0.5);
    ortho::正射影を作る(中心, 半幅(0), 半幅(1), 半幅(2), キャスター余白)
}
