//! カメラ相対ビュー射影から視錐台の隅を復元し、深度区間で切り出したスライスの8隅を返す工程。
//! 受け取るのはカメラ相対フレームのビュー射影、返すのは同じフレームの隅の座標である。
//! カメラが原点にあるフレームで扱うため、大域原点を動かしても値が1つも変わらない(カメラ相対契約)。

use glam::Vec3;

use blitz_math::{クリップ, メートル, ワールド, 位置, 変換};

use super::band::距離区分の区間;

/// 視錐台を回転に依らず表す量の組。包囲球の閉じた式がこれだけで書けるため、隅の座標と分けて持つ。
/// `半径比`は視軸からの隅の距離を深度で割った比であり、視錐台のどの深度でも同じ値になる。
pub(super) struct 視錐台の軸 {
    pub(super) 前方: Vec3,
    pub(super) 近深度: メートル,
    pub(super) 遠深度: メートル,
    pub(super) 半径比: f32,
}

/// 復元済みのカメラ視錐台。隅の並びは近平面4つ・遠平面4つで、同じ添字どうしが1本の稜線を作る。
pub(super) struct カメラ視錐台 {
    近隅一覧: [Vec3; 4],
    遠隅一覧: [Vec3; 4],
    近深度: f32,
    遠深度: f32,
}

impl カメラ視錐台 {
    /// クリップ空間の8隅を逆ビュー射影で戻す。逆行列が退化していれば`None`を返す。
    pub(super) fn 復元する(ビュー射影: 変換<ワールド, クリップ>) -> Option<Self> {
        let 逆 = ビュー射影.逆変換する();
        let 隅 = |x: f32, y: f32, z: f32| {
            let 点 = 逆.適用する(位置::<クリップ>::生成する(
                メートル::生成する(x),
                メートル::生成する(y),
                メートル::生成する(z),
            ));
            Vec3::new(点.x().値(), 点.y().値(), 点.z().値())
        };
        let 平面 = |z: f32| [隅(-1.0, -1.0, z), 隅(1.0, -1.0, z), 隅(1.0, 1.0, z), 隅(-1.0, 1.0, z)];
        let 近隅一覧 = 平面(1.0);
        let 遠隅一覧 = 平面(0.0);
        if 近隅一覧.iter().chain(遠隅一覧.iter()).any(|隅| !隅.is_finite()) {
            return None;
        }
        let 近深度 = 中心(&近隅一覧).length();
        let 遠深度 = 中心(&遠隅一覧).length();
        if !(近深度.is_finite() && 遠深度.is_finite()) || 近深度 <= 0.0 || 遠深度 <= 近深度 {
            return None;
        }
        Some(Self {
            近隅一覧,
            遠隅一覧,
            近深度,
            遠深度,
        })
    }

    pub(super) fn 軸(&self) -> 視錐台の軸 {
        let 近中心 = 中心(&self.近隅一覧);
        視錐台の軸 {
            前方: (中心(&self.遠隅一覧) - 近中心).normalize_or_zero(),
            近深度: メートル::生成する(self.近深度),
            遠深度: メートル::生成する(self.遠深度),
            半径比: (self.近隅一覧[0] - 近中心).length() / self.近深度,
        }
    }

    /// 深度区間で切り出したスライスの8隅。稜線上の位置はビュー空間深度に対して線形のため、
    /// 近隅と遠隅の線形補間がそのまま指定深度の隅になる。
    pub(super) fn スライスの隅(&self, 区間: 距離区分の区間) -> [位置<ワールド>; 8] {
        let 割合 = |深度: メートル| (深度.値() - self.近深度) / (self.遠深度 - self.近深度);
        let 近割合 = 割合(区間.近深度());
        let 遠割合 = 割合(区間.遠深度());
        std::array::from_fn(|添字| {
            let 稜線 = 添字 % 4;
            let 割合 = if 添字 < 4 { 近割合 } else { 遠割合 };
            let 点 = self.近隅一覧[稜線].lerp(self.遠隅一覧[稜線], 割合);
            位置::生成する(メートル::生成する(点.x), メートル::生成する(点.y), メートル::生成する(点.z))
        })
    }
}

fn 中心(隅一覧: &[Vec3; 4]) -> Vec3 {
    (隅一覧[0] + 隅一覧[1] + 隅一覧[2] + 隅一覧[3]) * 0.25
}
