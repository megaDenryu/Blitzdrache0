//! 帯の正射影の中心を、光空間に張った格子の最近傍へ寄せる工程(テクセルスナップ)。
//! 受け取るのは寄せる前の大域位置・格子の基準点・光の向き・格子の刻み、返すのは寄せた後の大域位置である。
//!
//! この工程が守る契約は、カメラが1テクセル未満どの向きへ動いても、静止した大域点の光源クリップ座標
//! (テクセル座標)が変わらないことである。カメラ相対描画では相対フレーム原点が動けば行列そのものは変わり、
//! 同じ静止物の相対座標も逆向きに変わるため、不変なのは行列でなく両者を合成した結果である。
//!
//! 影の泳ぎを止めるのに要るのは光の横断面2軸の量子化だけだが、光の向きに沿った軸も同じ刻みで量子化する。
//! こうすると量子化を軸ごとに場合分けせず、寄せ先を1つの格子の最近傍として向きの条件なしで書ける。
//! 沿った軸のずれ(最大で半テクセル)はキャスター余白が吸収する。
//!
//! 格子をカメラでなく世界へ固定するため、基準点にはシーンが決めた影の注視点(大域位置)を使う。
//! カメラ相対フレームで格子を張ると、カメラが動くたびに格子ごと動いて静止物の影が泳ぐ。
//! 世界の絶対座標へ直接張ると、世界全体を平行移動したときに格子の位相が変わって原点移動不変性が壊れる。
//! シーンとともに平行移動する基準点からの相対で張ると、その両方を満たす。
//!
//! 注意: f64の生値をここで扱うのは、格子の刻みが大域座標の桁に対して十分小さく、f32へ狭めてから
//! 量子化すると刻みが表現できないためである。生値が出るのはこのファイルの内側だけに閉じている。

use glam::DVec3;

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};

pub(super) fn 光空間の格子へ寄せる(
    位置: 大域ワールド位置,
    基準: 大域ワールド位置,
    光の向き: [f32; 3],
    刻み: メートル,
) -> 大域ワールド位置 {
    let 刻み = f64::from(刻み.値());
    if !刻み.is_finite() || 刻み <= 0.0 {
        return 位置;
    }
    let 基底 = 光空間の基底(光の向き);
    let ずれ = ベクトルにする(位置) - ベクトルにする(基準);
    let mut 寄せたずれ = DVec3::ZERO;
    for 軸 in 基底 {
        let 成分 = ずれ.dot(軸);
        寄せたずれ += 軸 * ((成分 / 刻み).round() * 刻み);
    }
    位置から生成する(ベクトルにする(基準) + 寄せたずれ)
}

/// 光の向きを1軸に取る直交基底。上向きの手掛かりは+Yを既定とし、光が真上または真下に近いときだけ+Zへ替える。
/// 手掛かりと光が平行だと外積が0になり基底が作れないためである。
fn 光空間の基底(光の向き: [f32; 3]) -> [DVec3; 3] {
    let 前 = DVec3::new(f64::from(光の向き[0]), f64::from(光の向き[1]), f64::from(光の向き[2])).normalize_or_zero();
    let 手掛かり = if 前.y.abs() > 0.999 { DVec3::Z } else { DVec3::Y };
    let 右 = 前.cross(手掛かり).normalize_or_zero();
    [右, 右.cross(前), 前]
}

fn ベクトルにする(位置: 大域ワールド位置) -> DVec3 {
    DVec3::new(位置.x().値(), 位置.y().値(), 位置.z().値())
}

fn 位置から生成する(ベクトル: DVec3) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(ベクトル.x),
        大域メートル::生成する(ベクトル.y),
        大域メートル::生成する(ベクトル.z),
    )
}
