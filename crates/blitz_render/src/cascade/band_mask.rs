//! 距離区分の集合。群の粗い判定が「この群はどの距離区分と交差するか」を作り、個体の判定はマスクが立った距離区分だけを調べる。
//! 距離区分を4つの真偽値で持ち回らず1つの型にするのは、立っている距離区分だけを走査する規律をこの型が持てるためであり、
//! 全個体へ常に距離区分数ぶんの判定を行う実装を避ける根拠にもなる
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」)。
//!
//! ビットの位置は距離区分番号の添字であり、距離区分数が4であるためu8の下位4ビットだけを使う。

use super::距離区分番号;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 距離区分マスク {
    ビット列: u8,
}

impl 距離区分マスク {
    /// どの距離区分とも交差しない。群がすべての距離区分の外にあるとき、その群の個体は1件も影を落とさない。
    pub fn 空() -> Self {
        Self::default()
    }

    /// すべての距離区分と交差する。距離区分別に絞らない実行で、どの距離区分も全個体を可視として扱うときに使う。
    pub fn 全距離区分() -> Self {
        距離区分番号::全距離区分().into_iter().fold(Self::空(), Self::距離区分を立てる)
    }

    pub fn 距離区分を立てる(self, 番号: 距離区分番号) -> Self {
        Self {
            ビット列: self.ビット列 | Self::ビット(番号),
        }
    }

    pub fn 立っているか(self, 番号: 距離区分番号) -> bool {
        self.ビット列 & Self::ビット(番号) != 0
    }

    pub fn 空か(self) -> bool {
        self.ビット列 == 0
    }

    /// ビットの位置が距離区分番号の添字である値そのもの。可視ID列のパス別のビット列は、シーンパスが先頭1本を
    /// 占めるぶんだけこの値を左へずらして組み立てる(`blitz_engine`の`可視パス集合`)。1個体につきパス5本を
    /// 列挙して述語を評価し直す形を避け、数え上げと並べ替えをビット演算だけで済ませるために公開する。
    pub fn ビット列(self) -> u8 {
        self.ビット列
    }

    fn ビット(番号: 距離区分番号) -> u8 {
        1u8 << 番号.添字()
    }
}
