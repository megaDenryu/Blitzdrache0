//! 帯の集合。群の粗い判定が「この群はどの帯と交差するか」を作り、個体の判定はマスクが立った帯だけを調べる。
//! 帯を4つの真偽値で持ち回らず1つの型にするのは、立っている帯だけを走査する規律をこの型が持てるためであり、
//! 全個体へ常に帯数ぶんの判定を行う実装を避ける根拠にもなる
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の帯別区間(4区分並べの後継)」)。
//!
//! ビットの位置は帯番号の添字であり、帯数が4であるためu8の下位4ビットだけを使う。

use super::帯番号;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 帯マスク {
    ビット列: u8,
}

impl 帯マスク {
    /// どの帯とも交差しない。群がすべての帯の外にあるとき、その群の個体は1件も影を落とさない。
    pub fn 空() -> Self {
        Self::default()
    }

    /// すべての帯と交差する。帯別に絞らない実行で、どの帯も全個体を可視として扱うときに使う。
    pub fn 全帯() -> Self {
        帯番号::全帯().into_iter().fold(Self::空(), Self::帯を立てる)
    }

    pub fn 帯を立てる(self, 番号: 帯番号) -> Self {
        Self {
            ビット列: self.ビット列 | Self::ビット(番号),
        }
    }

    pub fn 立っているか(self, 番号: 帯番号) -> bool {
        self.ビット列 & Self::ビット(番号) != 0
    }

    pub fn 空か(self) -> bool {
        self.ビット列 == 0
    }

    fn ビット(番号: 帯番号) -> u8 {
        1u8 << 番号.添字()
    }
}
