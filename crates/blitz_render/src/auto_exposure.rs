//! 自動露出のGPU境界の宣言。担当するのは「世界が起動時に決めた露出の決め方と、導出に要る定数をレンダラーへ運ぶ」ことである。
//!
//! 値を生の単精度で持つのは、この型がGPUへそのまま渡る境界だからである。単位と不変条件を型で守るのは
//! `crates/blitz_engine/src/auto_exposure/`のCPU正本の役目であり、コンポジションルートがその値を開いてここへ写す。
//!
//! ビンの境界の列を運ぶのは、GPUの写しがCPU正本と同じ単精度の定数を比べてビンを決めるためである。
//! 定数の二重台帳を作らず1つの列を配ることが、CPUとGPUでビンが1つもずれない契約の土台になる。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「順3-IIの実装設計」

/// 自動露出の2本のコンピュートシェーダー。集計が画素を数え、導出と適応が露出状態の永続バッファを更新する。
/// 2本を1つの束にするのは、片方だけを差し替えると数えた分布と読む分布が別物になるためである。
/// `導出と適応`は128個のビンを単一の呼び出しで走査する。
#[derive(Debug, Clone)]
pub struct 自動露出のシェーダー一式 {
    pub 集計シェーダー: crate::compute_shader::コンピュートシェーダー, // 明るさの圧縮前のHDR中間画像をビンと2つの枠へ数え上げる
    pub 導出と適応: crate::compute_shader::コンピュートシェーダー,     // ビンを添字の昇順に走査し、目標を導いて時間適応まで進める
}

/// ヒストグラムのビンの本数。CPU正本の`blitz_engine::auto_exposure::ビン数`と同じ値でなければならず、
/// 食い違いは`cargo xtask conform`の定数一致検査が拒む。
pub const ビン数: usize = 128;

/// 世界が宣言する露出の決め方。`時刻別固定`の補正段はフレーム描画入力の露出倍率に畳み込み済みで渡る。
/// `ヒストグラム自動`は芸術的バイアスだけを足し、時刻別固定の補正段は足さない
/// (同じ明るさを2つの系統が別々に動かさないため)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 露出方式 {
    時刻別固定,                                       // 昼夜方針が時刻から導く固定の補正段だけを使う
    ヒストグラム自動 { 芸術的バイアスの補正段: f32 }, // 画面全体の輝度ヒストグラムから導いた自動補正段を使う
}

impl 露出方式 {
    /// 集計と導出のパスをそのフレームへ積むか。時刻別固定の世界では1本も積まない。
    pub(crate) fn パスを積むか(self) -> bool {
        matches!(self, Self::ヒストグラム自動 { .. })
    }

    /// 明るさの圧縮へ渡す芸術的バイアスの段。時刻別固定の枝は自動補正を持たないため0である。
    pub(crate) fn 芸術的バイアスの補正段(self) -> f32 {
        match self {
            Self::時刻別固定 => 0.0,
            Self::ヒストグラム自動 {
                芸術的バイアスの補正段
            } => 芸術的バイアスの補正段,
        }
    }
}

/// 自動露出の資源を作るのに要る材料。露出方式が時刻別固定でも受け取るのは、資源の有無を方式で分けると
/// 明るさの圧縮のディスクリプタが世界ごとに違う形になり、束縛の一致条件が1つ増えるためである。
/// `境界の線形輝度`の各区間は下端を含み上端を含まない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 自動露出の設定 {
    pub 境界の線形輝度: [f32; ビン数], // 各ビンが覆う区間の下端を線形の相対輝度で表した列
    pub 目標中間灰の対数輝度: f32,     // 切り詰めた対数輝度の平均を写す先の明るさ
    pub 補正段の下限: f32,
    pub 補正段の上限: f32,
    pub 補正段を下げる速さ: f32, // 単位はEV段毎秒。画が明るくなったときに使う
    pub 補正段を上げる速さ: f32, // 単位はEV段毎秒。画が暗くなったときに使う
    pub 方式: 露出方式,
}

/// GPU上の自動露出を検収が読むための観測値。期待値も判定も持たず、CPU正本との突き合わせは
/// CPU正本を読めるコンポジションルートが行う。
/// 1フレームぶんのGPU上の自動露出の中身。`初期化済み`が偽のあいだ`補正段`は意味を持たない。
/// `直近の目標補正段`は時間適応を通す前の値である。`添字の重み付き総和の下位の語`と
/// `添字の重み付き総和の上位の語`は整数であるためCPU正本とバイト一致する。
#[derive(Debug, Clone, PartialEq)]
pub struct 自動露出の観測 {
    pub ビンの件数: [u32; ビン数],         // ビンごとの件数。添字はビンの添字と同じ並びである
    pub 零以下の件数: u32,                 // 0以下の輝度としてビンの外へ数えた件数
    pub 非有限の件数: u32,                 // 非有限の輝度としてビンの外へ数えた件数
    pub 初期化済み: bool,                  // 有効なヒストグラムから1度でも補正段を作ったか
    pub 補正段: f32,                       // 追従中の露出補正段(EV)
    pub 直近の目標補正段: f32,             // 直近に導出できたフレームの目標補正段(EV)
    pub 導出不能フレーム数: u32,           // ビンへ入った画素が1つも無く導出できなかったフレームの累計
    pub 添字の重み付き総和の下位の語: u32, // 直近に導出できたフレームの添字の重み付き総和の下位32ビット
    pub 添字の重み付き総和の上位の語: u32, // 同じ総和の上位32ビット
}
