//! 布素材の生成が距離拘束の内容と粒子の逆質量を検証することの検査。一辺2(粒子4)の最小の材料へ、GPUで範囲外アクセスか競合書き込みか非数になる
//! 反証(粒子数以上の端点・両端が同じ粒子・同じ色で端点を共有・負の静止長・非有限のコンプライアンス・逆質量0の粒子)を入れ、それぞれが型付きエラーになることを固定する。
//! 材料は`test_fixtures`が持つ。

use super::test_fixtures::{区間, 拘束, 材料, 粒子バイト列};
use super::*;

#[test]
fn 端点が別の粒子で同じ色が粒子を共有しない拘束は通る() {
    let 材料 = 材料(&[拘束(0, 1, 0.05, 0.0), 拘束(2, 3, 0.05, 0.01)], vec![区間(0, 2)]);
    assert!(布素材::生成する(材料).is_ok());
}

#[test]
fn 本数の合計がu32を超える色の区間を拒む() {
    let 材料 = 材料(&[拘束(0, 1, 0.05, 0.0)], vec![区間(0, u32::MAX), 区間(u32::MAX, 2)]);
    assert!(matches!(
        布素材::生成する(材料),
        Err(布素材エラー::色の区間の本数の合計がu32を超えた { 番号: 1 })
    ));
}

#[test]
fn 粒子数以上の端点を拒む() {
    let 材料 = 材料(&[拘束(0, 4, 0.05, 0.0)], vec![区間(0, 1)]);
    assert!(matches!(
        布素材::生成する(材料),
        Err(布素材エラー::拘束の端点が粒子数の範囲外 {
            拘束番号: 0,
            添字: 4,
            粒子数: 4
        })
    ));
}

#[test]
fn 両端が同じ粒子の拘束を拒む() {
    let 材料 = 材料(&[拘束(0, 1, 0.05, 0.0), 拘束(2, 2, 0.05, 0.0)], vec![区間(0, 2)]);
    assert!(matches!(
        布素材::生成する(材料),
        Err(布素材エラー::拘束の両端が同じ粒子 { 拘束番号: 1, 添字: 2 })
    ));
}

#[test]
fn 同じ色で粒子を共有する拘束を拒み別の色なら通す() {
    let 一色 = 材料(&[拘束(0, 1, 0.05, 0.0), 拘束(1, 2, 0.05, 0.0)], vec![区間(0, 2)]);
    assert!(matches!(
        布素材::生成する(一色),
        Err(布素材エラー::同じ色の拘束が粒子を共有する {
            色番号: 0,
            拘束番号: 1,
            添字: 1
        })
    ));
    let 二色 = 材料(&[拘束(0, 1, 0.05, 0.0), 拘束(1, 2, 0.05, 0.0)], vec![区間(0, 1), 区間(1, 1)]);
    assert!(布素材::生成する(二色).is_ok());
}

#[test]
fn 負の静止長を拒む() {
    let 材料 = 材料(&[拘束(0, 1, -0.05, 0.0)], vec![区間(0, 1)]);
    assert!(matches!(
        布素材::生成する(材料),
        Err(布素材エラー::拘束の静止長が0以上の有限でない { 拘束番号: 0, .. })
    ));
}

#[test]
fn 非有限のコンプライアンスを拒む() {
    let 材料 = 材料(&[拘束(0, 1, 0.05, f32::NAN)], vec![区間(0, 1)]);
    assert!(matches!(
        布素材::生成する(材料),
        Err(布素材エラー::拘束のコンプライアンスが0以上の有限でない { 拘束番号: 0, .. })
    ));
}

/// 反証: 逆質量0の粒子を通すと、固定を逆質量で表す旧い経路の入力が、どの拘束にも補正されず落ちる粒子として素材に残る。
#[test]
fn 逆質量が零の粒子を拒む() {
    let mut 材料 = 材料(&[拘束(0, 1, 0.05, 0.0)], vec![区間(0, 1)]);
    材料.粒子バイト列 = 粒子バイト列(0.0);
    assert!(matches!(
        布素材::生成する(材料),
        Err(布素材エラー::粒子の逆質量が正の有限でない { 粒子番号: 0, .. })
    ));
}
