//! 布素材の生成が拘束の内容を検証することの検査。一辺2(粒子4)の最小の材料へ、GPUで範囲外アクセスか競合書き込みか非数になる
//! 5つの反証(粒子数以上の端点・両端が同じ粒子・同じ色で端点を共有・負の静止長・非有限のコンプライアンス)を入れ、それぞれが型付きエラーになることを固定する。

use blitz_math::秒;

use super::*;

fn 拘束(a: u32, b: u32, 静止長: f32, コンプライアンス: f32) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(16);
    バイト列.extend_from_slice(&a.to_le_bytes());
    バイト列.extend_from_slice(&b.to_le_bytes());
    バイト列.extend_from_slice(&静止長.to_le_bytes());
    バイト列.extend_from_slice(&コンプライアンス.to_le_bytes());
    バイト列
}

fn 区間(開始: u32, 本数: u32) -> 布の彩色の区間 {
    布の彩色の区間 { 開始, 本数 }
}

/// 一辺2(粒子4)の材料。拘束は与えたバイト列をそのまま並べ、乗数はその本数ぶんの零である。
fn 材料(拘束一覧: &[Vec<u8>], 色の区間一覧: Vec<布の彩色の区間>) -> 布素材の材料 {
    let 刻み幅 = match 布の刻み幅::生成する(秒::生成する(1.0 / 60.0)) {
        Ok(刻み幅) => 刻み幅,
        Err(誤り) => panic!("検査の刻み幅が作れない: {誤り}"),
    };
    布素材の材料 {
        粒子バイト列: vec![0u8; 4 * 32],
        拘束の引数バイト列: 拘束一覧.concat(),
        ラグランジュ乗数の初期バイト列: vec![0u8; 拘束一覧.len() * 4],
        色の区間一覧,
        インデックス一覧: Vec::new(),
        アタッチ対応一覧: Vec::new(),
        一辺粒子数: 2,
        定数: 布定数 {
            重力: [0.0, -9.8, 0.0],
            粒子間隔: 0.05,
            グリッド原点: [0.0; 3],
            速度減衰: 0.99,
            自己衝突: 布の自己衝突::行わない,
            刻み幅,
        },
    }
}

#[test]
fn 端点が別の粒子で同じ色が粒子を共有しない拘束は通る() {
    let 材料 = 材料(&[拘束(0, 1, 0.05, 0.0), 拘束(2, 3, 0.05, 0.01)], vec![区間(0, 2)]);
    assert!(布素材::生成する(材料).is_ok());
}

#[test]
fn 粒子数以上の端点を拒む() {
    let 材料 = 材料(&[拘束(0, 4, 0.05, 0.0)], vec![区間(0, 1)]);
    assert!(matches!(
        布素材::生成する(材料),
        Err(布素材エラー::拘束の端点が粒子数の範囲外 {
            拘束番号: 0,
            添字: 4,
            粒子数: 4
        })
    ));
}

#[test]
fn 両端が同じ粒子の拘束を拒む() {
    let 材料 = 材料(&[拘束(0, 1, 0.05, 0.0), 拘束(2, 2, 0.05, 0.0)], vec![区間(0, 2)]);
    assert!(matches!(
        布素材::生成する(材料),
        Err(布素材エラー::拘束の両端が同じ粒子 { 拘束番号: 1, 添字: 2 })
    ));
}

#[test]
fn 同じ色で粒子を共有する拘束を拒み別の色なら通す() {
    let 一色 = 材料(&[拘束(0, 1, 0.05, 0.0), 拘束(1, 2, 0.05, 0.0)], vec![区間(0, 2)]);
    assert!(matches!(
        布素材::生成する(一色),
        Err(布素材エラー::同じ色の拘束が粒子を共有する {
            色番号: 0,
            拘束番号: 1,
            添字: 1
        })
    ));
    let 二色 = 材料(&[拘束(0, 1, 0.05, 0.0), 拘束(1, 2, 0.05, 0.0)], vec![区間(0, 1), 区間(1, 1)]);
    assert!(布素材::生成する(二色).is_ok());
}

#[test]
fn 負の静止長を拒む() {
    let 材料 = 材料(&[拘束(0, 1, -0.05, 0.0)], vec![区間(0, 1)]);
    assert!(matches!(
        布素材::生成する(材料),
        Err(布素材エラー::拘束の静止長が0以上の有限でない { 拘束番号: 0, .. })
    ));
}

#[test]
fn 非有限のコンプライアンスを拒む() {
    let 材料 = 材料(&[拘束(0, 1, 0.05, f32::NAN)], vec![区間(0, 1)]);
    assert!(matches!(
        布素材::生成する(材料),
        Err(布素材エラー::拘束のコンプライアンスが0以上の有限でない { 拘束番号: 0, .. })
    ));
}
