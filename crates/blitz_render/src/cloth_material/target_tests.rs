//! 布素材の生成が目標拘束の内容を検証することの検査。距離拘束と同じ5つの反証(粒子数以上の粒子・同じ粒子を持つ2本目・負のコンプライアンス・
//! 非有限の目標位置・1でも0でもない有効)に、乗数の長さの不一致と更新対応の添字の範囲外を足し、それぞれが型付きエラーになることを固定する。
//! 材料は`test_fixtures`が持つ。

use super::test_fixtures::{区間, 拘束, 目標位置, 目標拘束, 目標拘束つきの材料};
use super::*;

const 原点: [f32; 3] = [0.0, 0.0, 0.0];

#[test]
fn 別の粒子を持つ目標拘束は通り乗数は距離と目標の合計で数える() {
    let 材料 = 目標拘束つきの材料(
        &[拘束(0, 1, 0.05, 0.0)],
        vec![区間(0, 1)],
        &[目標拘束(0, 0.0), 目標拘束(3, 0.01)],
        &[目標位置(原点, 1.0), 目標位置(原点, 0.0)],
    );
    assert_eq!(材料.ラグランジュ乗数の初期バイト列.len(), 3 * 4);
    let 素材 = 布素材::生成する(材料);
    assert!(matches!(素材, Ok(素材) if 素材.目標拘束の数 == 2 && 素材.拘束の数 == 1));
}

#[test]
fn 粒子数以上の粒子を持つ目標拘束を拒む() {
    let 材料 = 目標拘束つきの材料(&[拘束(0, 1, 0.05, 0.0)], vec![区間(0, 1)], &[目標拘束(4, 0.0)], &[目標位置(原点, 1.0)]);
    assert!(matches!(
        布素材::生成する(材料),
        Err(布素材エラー::目標拘束の粒子が粒子数の範囲外 {
            拘束番号: 0,
            添字: 4,
            粒子数: 4
        })
    ));
}

#[test]
fn 同じ粒子を持つ2本目の目標拘束を拒む() {
    let 材料 = 目標拘束つきの材料(
        &[拘束(0, 1, 0.05, 0.0)],
        vec![区間(0, 1)],
        &[目標拘束(2, 0.0), 目標拘束(2, 0.0)],
        &[目標位置(原点, 1.0), 目標位置(原点, 1.0)],
    );
    assert!(matches!(
        布素材::生成する(材料),
        Err(布素材エラー::同じ粒子を持つ目標拘束が複数ある { 拘束番号: 1, 添字: 2 })
    ));
}

#[test]
fn 負のコンプライアンスと非有限の目標位置と1でも0でもない有効を拒む() {
    let 負 = 目標拘束つきの材料(&[拘束(0, 1, 0.05, 0.0)], vec![区間(0, 1)], &[目標拘束(2, -1.0)], &[目標位置(原点, 1.0)]);
    assert!(matches!(
        布素材::生成する(負),
        Err(布素材エラー::目標拘束のコンプライアンスが0以上の有限でない { 拘束番号: 0, .. })
    ));
    let 非有限 = 目標拘束つきの材料(
        &[拘束(0, 1, 0.05, 0.0)],
        vec![区間(0, 1)],
        &[目標拘束(2, 0.0)],
        &[目標位置([0.0, f32::INFINITY, 0.0], 1.0)],
    );
    assert!(matches!(
        布素材::生成する(非有限),
        Err(布素材エラー::目標位置が有限でない { 拘束番号: 0, .. })
    ));
    let 半端な有効 = 目標拘束つきの材料(&[拘束(0, 1, 0.05, 0.0)], vec![区間(0, 1)], &[目標拘束(2, 0.0)], &[目標位置(原点, 0.5)]);
    assert!(matches!(
        布素材::生成する(半端な有効),
        Err(布素材エラー::目標拘束の有効が1か0でない { 拘束番号: 0, .. })
    ));
}

/// 反証: 乗数を距離拘束の本数だけで数えると、目標拘束の乗数がバッファの範囲外へ書かれる。
#[test]
fn 目標拘束を数えない乗数の長さと範囲外の更新対応を拒む() {
    let mut 短い = 目標拘束つきの材料(&[拘束(0, 1, 0.05, 0.0)], vec![区間(0, 1)], &[目標拘束(2, 0.0)], &[目標位置(原点, 1.0)]);
    短い.ラグランジュ乗数の初期バイト列 = vec![0u8; 4];
    assert!(matches!(
        布素材::生成する(短い),
        Err(布素材エラー::バイト列長不一致 {
            名前: "ラグランジュ乗数の初期バイト列",
            期待: 8,
            実際: 4
        })
    ));
    let mut 範囲外 = 目標拘束つきの材料(&[拘束(0, 1, 0.05, 0.0)], vec![区間(0, 1)], &[目標拘束(2, 0.0)], &[目標位置(原点, 1.0)]);
    範囲外.目標の更新対応一覧 = vec![[1, 0]];
    assert!(matches!(
        布素材::生成する(範囲外),
        Err(布素材エラー::目標の更新対応の拘束添字が範囲外 {
            添字: 1, 目標拘束の数: 1
        })
    ));
}
