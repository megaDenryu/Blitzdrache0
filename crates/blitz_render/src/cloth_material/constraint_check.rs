//! 拘束の引数バイト列の内容の検証。受け取るのは拘束の引数バイト列・粒子数・色の区間一覧、返すのは拒む理由の型付きエラーである。
//! 長さと区間だけの検証では、粒子数以上の端点(GPUの`particles[添字 * 2]`が範囲外)・両端が同じ粒子・同じ色で粒子を共有する拘束
//! (1色の中で同じ位置へ競合して書く)・負や非有限の静止長とコンプライアンス(補正と乗数が非数になる)が素材の生成を通るため、ここが拒む。
//! 1拘束16バイト(a添字u32・b添字u32・静止長f32・コンプライアンスf32、リトルエンディアン)の読み方は`blitz_sim::gpu_layout::xpbd`の
//! 書き手の契約の写しである。blitz_renderはblitz_simへ依存しないため読み手をここへ置き、1件のバイト数は`cargo xtask conform`の
//! 定数の組が正本と突き合わせる。

use super::coloring::拘束1件のバイト数;
use super::{布の彩色の区間, 布素材エラー};

/// 前提: バイト列の長さは拘束1件のバイト数の倍数であり、区間一覧は先頭から隙間なく拘束を覆う(どちらも`coloring`が先に検証する)。
pub(super) fn 拘束の内容を検証する(
    バイト列: &[u8], 粒子数: u32, 区間一覧: &[布の彩色の区間]
) -> Result<(), 布素材エラー> {
    let mut 端点を使った色 = vec![0usize; 添字をusizeへ変換する(粒子数)]; // 0は未使用、それ以外は色番号 + 1
    for (色番号, 区間) in 区間一覧.iter().enumerate() {
        for 拘束番号 in 区間.開始..区間.開始 + 区間.本数 {
            let 読み = 拘束の引数の読み::読む(バイト列, 拘束番号);
            読み.定義域を検証する(拘束番号, 粒子数)?;
            for 添字 in [読み.a, 読み.b] {
                let 印 = &mut 端点を使った色[添字をusizeへ変換する(添字)];
                if *印 == 色番号 + 1 {
                    return Err(布素材エラー::同じ色の拘束が粒子を共有する {
                        色番号, 拘束番号, 添字
                    });
                }
                *印 = 色番号 + 1;
            }
        }
    }
    Ok(())
}

// 拘束1件をバイト列から読んだ値。
struct 拘束の引数の読み {
    a: u32,
    b: u32,
    静止長: f32,
    コンプライアンス: f32,
}

impl 拘束の引数の読み {
    fn 読む(バイト列: &[u8], 拘束番号: u32) -> Self {
        let 開始 = 添字をusizeへ変換する(拘束番号) * 拘束1件のバイト数;
        Self {
            a: u32::from_le_bytes(四バイトを読む(バイト列, 開始)),
            b: u32::from_le_bytes(四バイトを読む(バイト列, 開始 + 4)),
            静止長: f32::from_le_bytes(四バイトを読む(バイト列, 開始 + 8)),
            コンプライアンス: f32::from_le_bytes(四バイトを読む(バイト列, 開始 + 12)),
        }
    }

    // 端点が粒子数未満で互いに別の粒子であり、静止長とコンプライアンスが0以上の有限であることを確かめる。
    fn 定義域を検証する(&self, 拘束番号: u32, 粒子数: u32) -> Result<(), 布素材エラー> {
        for 添字 in [self.a, self.b] {
            if 添字 >= 粒子数 {
                return Err(布素材エラー::拘束の端点が粒子数の範囲外 {
                    拘束番号, 添字, 粒子数
                });
            }
        }
        if self.a == self.b {
            return Err(布素材エラー::拘束の両端が同じ粒子 {
                拘束番号, 添字: self.a
            });
        }
        if !(self.静止長.is_finite() && self.静止長 >= 0.0) {
            return Err(布素材エラー::拘束の静止長が0以上の有限でない {
                拘束番号,
                静止長: self.静止長,
            });
        }
        if !(self.コンプライアンス.is_finite() && self.コンプライアンス >= 0.0) {
            return Err(布素材エラー::拘束のコンプライアンスが0以上の有限でない {
                拘束番号,
                コンプライアンス: self.コンプライアンス,
            });
        }
        Ok(())
    }
}

fn 四バイトを読む(バイト列: &[u8], 開始: usize) -> [u8; 4] {
    [バイト列[開始], バイト列[開始 + 1], バイト列[開始 + 2], バイト列[開始 + 3]]
}

fn 添字をusizeへ変換する(値: u32) -> usize {
    usize::try_from(値).unwrap_or_else(|_| panic!("添字{値}がusizeに収まらない"))
}
