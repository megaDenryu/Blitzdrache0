//! 布素材を組む材料: 布素材の生成の口が受け取る値の束であり、検証はまだ済んでいない。blitz_simが作ったバイト列と一覧をそのまま運び、
//! 検証(`布素材::生成する`)を通って初めて`布素材`になる。固定・アタッチ・掴みは目標拘束(判断6)であり、粒子の逆質量は物性のまま全粒子が正である。

use super::coloring::布の彩色の区間;
use super::constants::布定数;
use super::target_update_pair::目標の更新対応;

/// 布素材の検証前の材料。フィールドの意味は各バイト列の書き手(`blitz_sim::gpu_layout`)の契約に従う。
#[derive(Debug, Clone)]
pub struct 布素材の材料 {
    pub 粒子バイト列: Vec<u8>,
    pub 拘束の引数バイト列: Vec<u8>,             // 彩色で並べ替えた順の距離拘束(a添字・b添字・静止長・コンプライアンス)
    pub ラグランジュ乗数の初期バイト列: Vec<u8>, // 距離拘束と目標拘束と曲げ拘束の合計ぶん、拘束ごと4バイト。刻みの開始でGPUが零へ戻す
    pub 色の区間一覧: Vec<布の彩色の区間>,
    pub 目標拘束の引数バイト列: Vec<u8>, // 目標拘束ごと8バイト(粒子添字・コンプライアンス)。世界固定点・アタッチ・掴みの枠
    pub 目標位置の初期バイト列: Vec<u8>, // 目標拘束ごと16バイト(目標位置xyz・有効)。動く目標と介入がGPUで書き換える
    pub 目標の更新対応一覧: Vec<目標の更新対応>, // 反復の前にスキン済み頂点の位置をその目標へ写す
    pub 曲げ拘束の引数バイト列: Vec<u8>, // 彩色で並べ替えた順の曲げ拘束(4点の添字・静止角・曲げのコンプライアンス)。乗数は目標拘束の後ろに続く
    pub 曲げの色の区間一覧: Vec<布の彩色の区間>, // 曲げ拘束の彩色の色ごとの区間。距離拘束の色の後ろに積む
    pub インデックス一覧: Vec<u32>,
    pub 一辺粒子数: u32,
    pub 定数: 布定数,
}
