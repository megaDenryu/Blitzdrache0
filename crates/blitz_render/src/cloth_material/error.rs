//! 布素材の生成が拒む入力。どの前提がどう破れたかを枝で言う。

use thiserror::Error;

#[derive(Debug, Error, Clone, Copy, PartialEq)]
pub enum 布素材エラー {
    #[error("一辺粒子数{0}が2未満だった")]
    一辺粒子数不足(u32),
    #[error("{名前}のバイト列長{実際}が期待{期待}と一致しない")]
    バイト列長不一致 { 名前: &'static str, 期待: usize, 実際: usize },
    #[error("{名前}の布粒子添字{添字}が粒子数{粒子数}の範囲外だった")]
    布粒子添字範囲外 { 名前: &'static str, 添字: u32, 粒子数: u32 },
    #[error("粒子{粒子番号}の逆質量{逆質量}が正の有限でない(固定は目標拘束で表すため逆質量0の粒子は無く、非有限は位置を非数にする)")]
    粒子の逆質量が正の有限でない { 粒子番号: usize, 逆質量: f32 },
    #[error("拘束の引数バイト列長{バイト長}が拘束1件の16バイトの倍数でないか、拘束が1本も無い")]
    拘束の引数バイト列が拘束の並びでない { バイト長: usize },
    #[error("色の区間{番号}の開始{開始}が直前までの本数の合計{期待する開始}と一致しない")]
    色の区間が連続していない { 番号: usize, 開始: u32, 期待する開始: u32 },
    #[error("色の区間{番号}までの本数の合計がu32を超えた(合計が巻き戻ると被覆の検査を通り、拘束の内容の読みが範囲外になる)")]
    色の区間の本数の合計がu32を超えた { 番号: usize },
    #[error("色の区間の本数の合計{合計}が拘束の数{拘束の数}と一致しない")]
    色の区間が拘束を覆わない { 合計: u32, 拘束の数: u32 },
    #[error("色の数{色の数}が上限{上限}を超えた(1刻みのパス数の上限がこの値から決まる)")]
    色の数が上限を超えた { 色の数: usize, 上限: u32 },
    #[error("布の刻み幅{秒}秒が正の有限値でない(GPUは刻み幅とその2乗の逆数を積分と刻み依存量に使う)")]
    刻み幅が正の有限値でない { 秒: f32 },
    #[error("拘束{拘束番号}の端点{添字}が粒子数{粒子数}の範囲外だった(GPUの粒子バッファの範囲外を読み書きする)")]
    拘束の端点が粒子数の範囲外 { 拘束番号: u32, 添字: u32, 粒子数: u32 },
    #[error("拘束{拘束番号}の両端が同じ粒子{添字}だった(距離拘束の向きが定まらない)")]
    拘束の両端が同じ粒子 { 拘束番号: u32, 添字: u32 },
    #[error("色{色番号}の拘束{拘束番号}が同じ色の別の拘束と粒子{添字}を共有する(1色の中で同じ位置へ競合して書く)")]
    同じ色の拘束が粒子を共有する { 色番号: usize, 拘束番号: u32, 添字: u32 },
    #[error("拘束{拘束番号}の静止長{静止長}が0以上の有限でない(補正と乗数が非数になる)")]
    拘束の静止長が0以上の有限でない { 拘束番号: u32, 静止長: f32 },
    #[error("拘束{拘束番号}のコンプライアンス{コンプライアンス}が0以上の有限でない(刻み依存量が非数か負になる)")]
    拘束のコンプライアンスが0以上の有限でない { 拘束番号: u32, コンプライアンス: f32 },
    #[error("目標拘束の引数バイト列長{バイト長}が目標拘束1件の8バイトの倍数でない")]
    目標拘束の引数バイト列が拘束の並びでない { バイト長: usize },
    #[error("目標拘束{拘束番号}の粒子{添字}が粒子数{粒子数}の範囲外だった(GPUの粒子バッファの範囲外を読み書きする)")]
    目標拘束の粒子が粒子数の範囲外 { 拘束番号: usize, 添字: u32, 粒子数: u32 },
    #[error("目標拘束{拘束番号}が別の目標拘束と粒子{添字}を共有する(目標拘束は1色で解くため、粒子1つにつき高々1本である)")]
    同じ粒子を持つ目標拘束が複数ある { 拘束番号: usize, 添字: u32 },
    #[error("目標拘束{拘束番号}のコンプライアンス{コンプライアンス}が0以上の有限でない(刻み依存量が非数か負になる)")]
    目標拘束のコンプライアンスが0以上の有限でない { 拘束番号: usize, コンプライアンス: f32 },
    #[error("目標拘束{拘束番号}の目標位置{位置:?}が有限でない(補正と乗数が非数になる)")]
    目標位置が有限でない { 拘束番号: usize, 位置: [f32; 3] },
    #[error("目標拘束{拘束番号}の有効{値}が1.0でも0.0でもない(GPUは0.0だけを無効と読む)")]
    目標拘束の有効が1か0でない { 拘束番号: usize, 値: f32 },
    #[error("目標の更新対応の目標拘束添字{添字}が目標拘束の数{目標拘束の数}の範囲外だった(目標位置バッファの範囲外へ書く)")]
    目標の更新対応の拘束添字が範囲外 { 添字: u32, 目標拘束の数: u32 },
}
