//! 布の物性以外の空間定数(重力・粒子間隔・グリッド原点・速度減衰・刻み幅)と、自己衝突を積むかどうかの別。値はアプリが与える。

use super::time_step_width::布の刻み幅;

/// 粒子どうしの自己衝突(空間ハッシュと分離の工程)を積むかどうか。CPUの参照計算との突き合わせは、分離が原子加算の順序に依って
/// CPUで再現できないため`行わない`で走らせる。本番の布は`行う`である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 布の自己衝突 {
    行う,
    行わない,
}

/// 布の物性・空間定数と刻み幅。単位はシーンのワールド単位(Foxは1単位約1cm)で、値はアプリが与える。
/// 布の硬さはここに無く、拘束の引数バイト列が拘束ごとに持つコンプライアンスが正本である(Issue #36「物性」)。
/// 刻み幅は時間の規律の基本刻みをコンポジションルートが注入した値であり、レンダラーは既定値を持たない。
#[derive(Debug, Clone, Copy)]
pub struct 布定数 {
    pub 重力: [f32; 3],
    pub 粒子間隔: f32,
    pub グリッド原点: [f32; 3],
    pub 速度減衰: f32,
    pub 自己衝突: 布の自己衝突,
    pub 刻み幅: 布の刻み幅,
}
