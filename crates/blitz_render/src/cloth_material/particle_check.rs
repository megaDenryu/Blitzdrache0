//! 粒子バイト列の逆質量の検証。固定は目標拘束で表すため、布に逆質量0の粒子は存在しない(`_doc/設計/XPBD共通拘束基盤.md`「判断6」)。
//! 積分と仕上げが全粒子へ同じ規則を当てる今の経路では、逆質量0の粒子は重力で落ちながらどの拘束にも補正されず、非有限の逆質量は位置を非数にするため、
//! 素材の生成で拒む。粒子1件は32バイト(位置xyz・逆質量・速度xyz・予備)であり、逆質量は先頭から12バイト目の単精度である。

use super::length_check::四バイトを読む;
use super::布素材エラー;

pub(super) const 粒子1件のバイト数: usize = 32;
const 逆質量の位置: usize = 12;

/// 前提: バイト列の長さは粒子1件のバイト数の倍数である(呼び出し側が先に検証する)。
pub(super) fn 逆質量を検証する(粒子バイト列: &[u8]) -> Result<(), 布素材エラー> {
    for (粒子番号, 粒子) in 粒子バイト列.chunks_exact(粒子1件のバイト数).enumerate() {
        let 逆質量 = f32::from_le_bytes(四バイトを読む(粒子, 逆質量の位置));
        if !(逆質量.is_finite() && 逆質量 > 0.0) {
            return Err(布素材エラー::粒子の逆質量が正の有限でない { 粒子番号, 逆質量 });
        }
    }
    Ok(())
}
