//! 曲げ拘束の引数バイト列の内容の検証。受け取るのは曲げ拘束の引数バイト列・粒子数・曲げの色の区間一覧、返すのは曲げ拘束の数か拒む理由の型付きエラーである。
//! 課すのは、4点が粒子数未満であること(GPUの`particles[添字 * 2]`が範囲外にならない)・4点が互いに別の粒子であること(同じ粒子があると三角形が潰れて
//! 法線が定まらず、反復の中で無言に無視され続ける)・同じ色の区間の中で粒子を共有しないこと(1色の中で同じ位置へ競合して書く)・静止角が有限で半周以内であること
//! (半周を越えると最短の弧へ畳んだ拘束違反と一致しない)・コンプライアンスが0以上の有限であること(刻み依存量が非数か負になる)である。
//! 1拘束24バイト(4点の添字u32・静止角f32・コンプライアンスf32、リトルエンディアン)の読み方は`blitz_sim::gpu_layout::xpbd`の書き手の契約の写しであり、
//! `cargo xtask conform`の定数の組が正本と突き合わせる。0本の布(一辺2の格子は斜め1本を持つが、検査の最小の材料は持たない)も許す。

use super::coloring::区間の並びを検証する;
use super::length_check::{四バイトを読む, 添字をusizeへ変換する};
use super::{布の彩色の区間, 布素材エラー};

pub(super) const 曲げ拘束1件のバイト数: usize = 24;

/// 布の曲げの彩色の色の数の上限。現在の布の格子(一辺32)は15色であり(`_doc/計測/布の曲げ拘束_2026-09-02.md`)、格子の並びの貪欲な彩色が15を超えないことを
/// blitz_simの検査が固定している。余裕を持たせるのは、一辺の変更で色が増えても素材の生成が落ちないようにするためであり、1刻みのパス数の上限がこの値から決まる。
pub const 布の曲げの彩色の色数上限: u32 = 18;

// 曲げ拘束の引数バイト列から数えた曲げ拘束の数。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 曲げ拘束の数(u32);

impl 曲げ拘束の数 {
    pub(super) fn 値(self) -> u32 {
        self.0
    }

    pub(super) fn 配列の長さ(self) -> usize {
        添字をusizeへ変換する(self.0)
    }
}

pub(super) fn 曲げ拘束の内容を検証する(
    バイト列: &[u8],
    粒子数: u32,
    区間一覧: &[布の彩色の区間],
) -> Result<曲げ拘束の数, 布素材エラー> {
    if !バイト列.len().is_multiple_of(曲げ拘束1件のバイト数) {
        return Err(布素材エラー::曲げ拘束の引数バイト列が拘束の並びでない {
            バイト長: バイト列.len()
        });
    }
    let 本数 = u32::try_from(バイト列.len() / 曲げ拘束1件のバイト数).unwrap_or_else(|_| panic!("曲げ拘束の数がu32に収まらない"));
    区間の並びを検証する(区間一覧, 本数, 布の曲げの彩色の色数上限)?;
    let mut 点を使った色 = vec![0usize; 添字をusizeへ変換する(粒子数)]; // 0は未使用、それ以外は色番号 + 1
    for (色番号, 区間) in 区間一覧.iter().enumerate() {
        for 拘束番号 in 区間.開始..区間.開始 + 区間.本数 {
            let 読み = 曲げ拘束の引数の読み::読む(バイト列, 拘束番号);
            読み.定義域を検証する(拘束番号, 粒子数)?;
            for 添字 in 読み.点一覧 {
                let 印 = &mut 点を使った色[添字をusizeへ変換する(添字)];
                if *印 == 色番号 + 1 {
                    return Err(布素材エラー::同じ色の曲げ拘束が粒子を共有する {
                        色番号, 拘束番号, 添字
                    });
                }
                *印 = 色番号 + 1;
            }
        }
    }
    Ok(曲げ拘束の数(本数))
}

// 曲げ拘束1件をバイト列から読んだ値。
struct 曲げ拘束の引数の読み {
    点一覧: [u32; 4],
    静止角: f32,
    コンプライアンス: f32,
}

impl 曲げ拘束の引数の読み {
    fn 読む(バイト列: &[u8], 拘束番号: u32) -> Self {
        let 開始 = 添字をusizeへ変換する(拘束番号) * 曲げ拘束1件のバイト数;
        let 語 = |番目: usize| 四バイトを読む(バイト列, 開始 + 番目 * 4);
        Self {
            点一覧: [
                u32::from_le_bytes(語(0)),
                u32::from_le_bytes(語(1)),
                u32::from_le_bytes(語(2)),
                u32::from_le_bytes(語(3)),
            ],
            静止角: f32::from_le_bytes(語(4)),
            コンプライアンス: f32::from_le_bytes(語(5)),
        }
    }

    // 4点が粒子数未満で互いに別の粒子であり、静止角が有限で半周以内、コンプライアンスが0以上の有限であることを確かめる。
    fn 定義域を検証する(&self, 拘束番号: u32, 粒子数: u32) -> Result<(), 布素材エラー> {
        for (先, 添字) in self.点一覧.iter().enumerate() {
            if *添字 >= 粒子数 {
                return Err(布素材エラー::曲げ拘束の点が粒子数の範囲外 {
                    拘束番号,
                    添字: *添字,
                    粒子数,
                });
            }
            if self.点一覧[先 + 1..].contains(添字) {
                return Err(布素材エラー::曲げ拘束が同じ粒子を持つ {
                    拘束番号, 添字: *添字
                });
            }
        }
        if !(self.静止角.is_finite() && self.静止角.abs() <= std::f32::consts::PI) {
            return Err(布素材エラー::曲げ拘束の静止角が半周以内の有限でない {
                拘束番号,
                静止角: self.静止角,
            });
        }
        if !(self.コンプライアンス.is_finite() && self.コンプライアンス >= 0.0) {
            return Err(布素材エラー::曲げ拘束のコンプライアンスが0以上の有限でない {
                拘束番号,
                コンプライアンス: self.コンプライアンス,
            });
        }
        Ok(())
    }
}
