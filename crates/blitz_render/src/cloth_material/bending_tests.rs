//! 布素材の生成が曲げ拘束の内容を検証することの検査。一辺2(粒子4)の最小の材料へ、GPUで範囲外アクセスか競合書き込みか非数になる反証
//! (粒子数以上の点・同じ粒子を2つ持つ・同じ色で粒子を共有・半周を越える静止角・負のコンプライアンス・区間が覆わない)を入れ、それぞれが型付きエラーになることを固定する。
//! 材料は`test_fixtures`が持つ。

use super::test_fixtures::{区間, 拘束, 曲げ拘束, 材料};
use super::*;

fn 曲げ拘束つきの材料(曲げ一覧: &[Vec<u8>], 曲げの色の区間一覧: Vec<布の彩色の区間>) -> 布素材の材料 {
    let mut 材料 = 材料(&[拘束(0, 1, 0.05, 0.0)], vec![区間(0, 1)]);
    材料.曲げ拘束の引数バイト列 = 曲げ一覧.concat();
    材料.曲げの色の区間一覧 = 曲げの色の区間一覧;
    材料.ラグランジュ乗数の初期バイト列 = vec![0u8; (1 + 曲げ一覧.len()) * 4];
    材料
}

#[test]
fn 四点が別の粒子で区間が覆う曲げ拘束は通り乗数の長さは距離と曲げの合計になる() {
    let 材料 = 曲げ拘束つきの材料(&[曲げ拘束([2, 1, 0, 3], 0.0, 10.0)], vec![区間(0, 1)]);
    let 素材 = 布素材::生成する(材料);
    assert!(matches!(素材, Ok(素材) if 素材.曲げ拘束の数 == 1));
    let 乗数が短い = {
        let mut 材料 = 曲げ拘束つきの材料(&[曲げ拘束([2, 1, 0, 3], 0.0, 10.0)], vec![区間(0, 1)]);
        材料.ラグランジュ乗数の初期バイト列 = vec![0u8; 4];
        材料
    };
    assert!(matches!(布素材::生成する(乗数が短い), Err(布素材エラー::バイト列長不一致 { .. })));
}

#[test]
fn 粒子数以上の点と同じ粒子を持つ曲げ拘束を拒む() {
    let 範囲外 = 曲げ拘束つきの材料(&[曲げ拘束([2, 1, 0, 4], 0.0, 0.0)], vec![区間(0, 1)]);
    assert!(matches!(
        布素材::生成する(範囲外),
        Err(布素材エラー::曲げ拘束の点が粒子数の範囲外 {
            拘束番号: 0,
            添字: 4,
            粒子数: 4
        })
    ));
    let 同じ粒子 = 曲げ拘束つきの材料(&[曲げ拘束([2, 1, 0, 1], 0.0, 0.0)], vec![区間(0, 1)]);
    assert!(matches!(
        布素材::生成する(同じ粒子),
        Err(布素材エラー::曲げ拘束が同じ粒子を持つ { 拘束番号: 0, 添字: 1 })
    ));
}

#[test]
fn 同じ色で粒子を共有する曲げ拘束を拒み別の色なら通す() {
    let 二本 = [曲げ拘束([0, 1, 2, 3], 0.0, 0.0), 曲げ拘束([3, 2, 1, 0], 0.0, 0.0)];
    let 一色 = 曲げ拘束つきの材料(&二本, vec![区間(0, 2)]);
    assert!(matches!(
        布素材::生成する(一色),
        Err(布素材エラー::同じ色の曲げ拘束が粒子を共有する {
            色番号: 0, 拘束番号: 1, ..
        })
    ));
    let 二色 = 曲げ拘束つきの材料(&二本, vec![区間(0, 1), 区間(1, 1)]);
    assert!(布素材::生成する(二色).is_ok());
}

#[test]
fn 半周を越える静止角と負のコンプライアンスと覆わない区間を拒む() {
    let 静止角 = 曲げ拘束つきの材料(&[曲げ拘束([2, 1, 0, 3], 4.0, 0.0)], vec![区間(0, 1)]);
    assert!(matches!(
        布素材::生成する(静止角),
        Err(布素材エラー::曲げ拘束の静止角が半周以内の有限でない { 拘束番号: 0, .. })
    ));
    let 負 = 曲げ拘束つきの材料(&[曲げ拘束([2, 1, 0, 3], 0.0, -1.0)], vec![区間(0, 1)]);
    assert!(matches!(
        布素材::生成する(負),
        Err(布素材エラー::曲げ拘束のコンプライアンスが0以上の有限でない { 拘束番号: 0, .. })
    ));
    let 覆わない = 曲げ拘束つきの材料(&[曲げ拘束([2, 1, 0, 3], 0.0, 0.0)], Vec::new());
    assert!(matches!(
        布素材::生成する(覆わない),
        Err(布素材エラー::色の区間が拘束を覆わない { 合計: 0, 拘束の数: 1 })
    ));
}
