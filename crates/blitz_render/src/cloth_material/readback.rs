//! GPUから写し取った布の粒子の位置とラグランジュ乗数。CPUの参照計算との突き合わせ(Issue #36・#37の検証)だけが読む。
//! 生の単精度で返すのは、検査が非有限値や発散を観測できなければならないためである。
//! 目標拘束と曲げ拘束の乗数は距離拘束の乗数の後ろに続く1本のGPUバッファから写し、読み戻しの器がここで3つの並びへ分ける。

/// 並びは素材の粒子の並び、彩色で並べ替えた距離拘束の並び、目標拘束のバッチの並び、彩色で並べ替えた曲げ拘束の並びそのものである。
#[derive(Debug, Clone, PartialEq)]
pub struct 布の読み戻し {
    pub 位置一覧: Vec<[f32; 3]>,
    pub ラグランジュ乗数一覧: Vec<f32>,
    pub 目標拘束のラグランジュ乗数一覧: Vec<f32>,
    pub 曲げ拘束のラグランジュ乗数一覧: Vec<f32>,
}
