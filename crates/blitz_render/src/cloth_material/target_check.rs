//! 目標拘束の引数バイト列と目標位置の初期バイト列の内容の検証。受け取るのは2本のバイト列と粒子数、返すのは目標拘束の数か拒む理由の型付きエラーである。
//! 課すのは、粒子添字が粒子数未満であること(GPUの`particles[添字 * 2]`が範囲外にならない)・同じ粒子を持つ目標拘束が高々1本であること(バッチ全体が1色で
//! 解けるための不変条件。2本あると1回のディスパッチの中で同じ粒子へ競合して書く)・コンプライアンスが0以上の有限であること・目標位置が有限であること・
//! 有効が1.0か0.0であること(GPUは0.0だけを無効と読む)である。1件のバイト数は`blitz_sim::gpu_layout::xpbd`の書き手の契約の写しであり、
//! `cargo xtask conform`の定数の組が正本と突き合わせる。
//! 目標の更新対応にも2つを課す。目標拘束添字が本数未満であること(目標位置バッファの範囲外へ書かない)・同じ目標拘束添字を2件が指さないこと
//! (目標の確定は対応1件につき1スレッドであり、2件が同じ拘束を指すと同じ目標位置へ同時に書いて目標が実行順に依存する)である。

use super::length_check::{四バイトを読む, 添字をusizeへ変換する};
use super::布素材エラー;

pub(super) const 目標拘束1件のバイト数: usize = 8;
pub(super) const 目標位置1件のバイト数: usize = 16;

/// 目標拘束の引数バイト列から数えた目標拘束の数。0本を許す(参照比較の布のように固定だけを持つ布は上端行の本数である)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 目標拘束の数(u32);

impl 目標拘束の数 {
    pub(super) fn 値(self) -> u32 {
        self.0
    }

    pub(super) fn 配列の長さ(self) -> usize {
        添字をusizeへ変換する(self.0)
    }
}

pub(super) fn 目標拘束の内容を検証する(
    引数バイト列: &[u8],
    目標位置バイト列: &[u8],
    粒子数: u32,
) -> Result<目標拘束の数, 布素材エラー> {
    if !引数バイト列.len().is_multiple_of(目標拘束1件のバイト数) {
        return Err(布素材エラー::目標拘束の引数バイト列が拘束の並びでない {
            バイト長: 引数バイト列.len(),
        });
    }
    let 本数 = 引数バイト列.len() / 目標拘束1件のバイト数;
    super::length_check::長さを検証する("目標位置の初期バイト列", 目標位置バイト列.len(), 本数 * 目標位置1件のバイト数)?;
    let mut 粒子を使った = vec![false; 添字をusizeへ変換する(粒子数)];
    for 拘束番号 in 0..本数 {
        let 引数 = &引数バイト列[拘束番号 * 目標拘束1件のバイト数..];
        let 目標 = &目標位置バイト列[拘束番号 * 目標位置1件のバイト数..];
        let 粒子添字 = u32::from_le_bytes(四バイトを読む(引数, 0));
        if 粒子添字 >= 粒子数 {
            return Err(布素材エラー::目標拘束の粒子が粒子数の範囲外 {
                拘束番号,
                添字: 粒子添字,
                粒子数,
            });
        }
        if 粒子を使った[添字をusizeへ変換する(粒子添字)] {
            return Err(布素材エラー::同じ粒子を持つ目標拘束が複数ある {
                拘束番号, 添字: 粒子添字
            });
        }
        粒子を使った[添字をusizeへ変換する(粒子添字)] = true;
        定義域を検証する(拘束番号, 引数, 目標)?;
    }
    Ok(目標拘束の数(
        u32::try_from(本数).unwrap_or_else(|_| panic!("目標拘束の数がu32に収まらない")),
    ))
}

fn 定義域を検証する(拘束番号: usize, 引数: &[u8], 目標: &[u8]) -> Result<(), 布素材エラー> {
    let コンプライアンス = f32::from_le_bytes(四バイトを読む(引数, 4));
    if !(コンプライアンス.is_finite() && コンプライアンス >= 0.0) {
        return Err(布素材エラー::目標拘束のコンプライアンスが0以上の有限でない {
            拘束番号, コンプライアンス
        });
    }
    let 位置 = [
        f32::from_le_bytes(四バイトを読む(目標, 0)),
        f32::from_le_bytes(四バイトを読む(目標, 4)),
        f32::from_le_bytes(四バイトを読む(目標, 8)),
    ];
    if !位置.iter().all(|成分| 成分.is_finite()) {
        return Err(布素材エラー::目標位置が有限でない { 拘束番号, 位置 });
    }
    let 有効 = f32::from_le_bytes(四バイトを読む(目標, 12));
    if 有効 != 0.0 && 有効 != 1.0 {
        return Err(布素材エラー::目標拘束の有効が1か0でない { 拘束番号, 値: 有効 });
    }
    Ok(())
}

/// 目標の更新対応(目標拘束添字・スキン頂点添字)の目標拘束添字が本数の範囲内で、対応の間で一意であることを確かめる。
pub(super) fn 更新対応を検証する(対応一覧: &[[u32; 2]], 本数: 目標拘束の数) -> Result<(), 布素材エラー> {
    let mut 拘束を指した対応番号: Vec<Option<usize>> = vec![None; 本数.配列の長さ()];
    for (対応番号, 対応) in 対応一覧.iter().enumerate() {
        let 添字 = 対応[0];
        if 添字 >= 本数.値() {
            return Err(布素材エラー::目標の更新対応の拘束添字が範囲外 {
                添字,
                目標拘束の数: 本数.値(),
            });
        }
        let 枠 = &mut 拘束を指した対応番号[添字をusizeへ変換する(添字)];
        if let Some(先の対応番号) = *枠 {
            return Err(布素材エラー::目標の更新対応の拘束添字が重複 {
                先の対応番号,
                後の対応番号: 対応番号,
                添字,
            });
        }
        *枠 = Some(対応番号);
    }
    Ok(())
}
