//! 布の彩色の区間と、その検証。区間は`blitz_sim::constraint_graph::色の区間`の写しであり、値だけを運ぶ
//! (blitz_renderはblitz_simに依存しないため型を共有しない)。
//! 色の数に上限を置くのは、布が1刻みに積むパスの数がこの値から決まり、パス別GPU計測のクエリプールの容量が
//! その上限から決まるためである。上限を越えた素材は生成で拒む。

use super::布素材エラー;

/// 布の彩色の色の数の上限。現在の布の格子(一辺32)は9色であり、格子の並びの貪欲な彩色が9を超えないことを
/// blitz_simの検査が固定している。余裕を持たせるのは、一辺の変更で色が1つ2つ増えても素材の生成が落ちないようにするためである。
pub const 布の彩色の色数上限: u32 = 12;

pub(super) const 拘束1件のバイト数: usize = 16;

/// 彩色の1色が占める、拘束の並びの中の連続した区間。GPUのディスパッチ1回分であり、プッシュ定数で運ぶ。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 布の彩色の区間 {
    pub 開始: u32,
    pub 本数: u32,
}

/// 拘束の引数バイト列から数えた拘束の数。1以上であることを生成が保証する。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 拘束の数(u32);

impl 拘束の数 {
    pub(super) fn 値(self) -> u32 {
        self.0
    }

    pub(super) fn 配列の長さ(self) -> usize {
        usize::try_from(self.0).unwrap_or_else(|_| panic!("拘束の数がusizeに収まらない"))
    }
}

pub(super) fn 拘束の数を読む(拘束の引数バイト列: &[u8]) -> Result<拘束の数, 布素材エラー> {
    let バイト長 = 拘束の引数バイト列.len();
    if バイト長 == 0 || !バイト長.is_multiple_of(拘束1件のバイト数) {
        return Err(布素材エラー::拘束の引数バイト列が拘束の並びでない { バイト長 });
    }
    let 本数 = u32::try_from(バイト長 / 拘束1件のバイト数).unwrap_or_else(|_| panic!("拘束の数がu32に収まらない"));
    Ok(拘束の数(本数))
}

/// 区間が先頭から隙間なく連続し、本数の合計が拘束の数と一致し、色の数が上限に収まることを確かめる。
pub(super) fn 色の区間を検証する(区間一覧: &[布の彩色の区間], 本数: 拘束の数) -> Result<(), 布素材エラー> {
    let mut 期待する開始 = 0u32;
    for (番号, 区間) in 区間一覧.iter().enumerate() {
        if 区間.開始 != 期待する開始 {
            return Err(布素材エラー::色の区間が連続していない {
                番号,
                開始: 区間.開始,
                期待する開始,
            });
        }
        // 公開の入力であるため、本数の合計がu32を越える区間(リリース版では合計が巻き戻って被覆の検査を通る)を型付きで拒む。
        期待する開始 = 期待する開始
            .checked_add(区間.本数)
            .ok_or(布素材エラー::色の区間の本数の合計がu32を超えた { 番号 })?;
    }
    if 期待する開始 != 本数.値() {
        return Err(布素材エラー::色の区間が拘束を覆わない {
            合計: 期待する開始,
            拘束の数: 本数.値(),
        });
    }
    if 区間一覧.len() > usize::try_from(布の彩色の色数上限).unwrap_or(usize::MAX) {
        return Err(布素材エラー::色の数が上限を超えた {
            色の数: 区間一覧.len(),
            上限: 布の彩色の色数上限,
        });
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn 区間(開始: u32, 本数: u32) -> 布の彩色の区間 {
        布の彩色の区間 { 開始, 本数 }
    }

    #[test]
    fn 連続して拘束を覆う区間だけを通す() {
        let 本数 = 拘束の数(5);
        assert!(色の区間を検証する(&[区間(0, 3), 区間(3, 2)], 本数).is_ok());
        assert!(matches!(
            色の区間を検証する(&[区間(0, 3), 区間(4, 1)], 本数),
            Err(布素材エラー::色の区間が連続していない { 番号: 1, .. })
        ));
        assert!(matches!(
            色の区間を検証する(&[区間(0, 3)], 本数),
            Err(布素材エラー::色の区間が拘束を覆わない { 合計: 3, 拘束の数: 5 })
        ));
    }

    #[test]
    fn 拘束の数はバイト列長の16分の1で零と端数は拒む() {
        assert_eq!(拘束の数を読む(&[0u8; 32]).map(拘束の数::値), Ok(2));
        assert!(拘束の数を読む(&[]).is_err());
        assert!(拘束の数を読む(&[0u8; 20]).is_err());
    }
}
