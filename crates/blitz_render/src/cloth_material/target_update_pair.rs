#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 目標の更新対応 {
    /// 位置を写す先の目標拘束。
    pub 目標拘束添字: 布の目標拘束添字,
    /// 位置を写す元のスキン済み頂点。
    pub スキン頂点添字: スキン頂点添字,
}
