//! 目標の更新対応: 目標の確定が反復の前にスキン済み頂点の位置を写す先の目標拘束と、写す元のスキン頂点の組。
//! 2つの添字を`[u32; 2]`で並べると要素の順を取り違えても型が通るため、名前の付いたフィールドで持つ。
