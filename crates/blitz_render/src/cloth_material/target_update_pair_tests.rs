//! 布素材の生成が目標の更新対応(目標拘束添字・スキン頂点添字)を検証することの検査。目標拘束添字の範囲外と、対応の間の重複が
//! それぞれ型付きエラーになり、別の目標拘束を指す2件は通ることを固定する。材料は`test_fixtures`が持つ。

use super::test_fixtures::{区間, 拘束, 更新対応, 目標位置, 目標拘束, 目標拘束つきの材料};
use super::*;

const 原点: [f32; 3] = [0.0, 0.0, 0.0];

// 目標拘束2本の材料へ、与えた更新対応(目標拘束添字, スキン頂点添字)の組を据える。
fn 更新対応を据えた材料(対応一覧: &[(u32, u32)]) -> 布素材の材料 {
    let mut 材料 = 目標拘束つきの材料(
        &[拘束(0, 1, 0.05, 0.0)],
        vec![区間(0, 1)],
        &[目標拘束(2, 0.0), 目標拘束(3, 0.0)],
        &[目標位置(原点, 1.0), 目標位置(原点, 1.0)],
    );
    材料.目標の更新対応一覧 = 対応一覧.iter().map(|&(目標拘束, スキン頂点)| 更新対応(目標拘束, スキン頂点)).collect();
    材料
}

// 反証: 範囲を検証しないと、目標の確定が目標位置バッファの範囲外へ書く。
#[test]
fn 範囲外の目標拘束を指す更新対応を拒む() {
    assert!(matches!(
        布素材::生成する(更新対応を据えた材料(&[(2, 0)])),
        Err(布素材エラー::目標の更新対応の拘束添字が範囲外 { 添字, 目標拘束の数: 2 }) if 添字 == 布の目標拘束添字::生成する(2)
    ));
}

// 反証: 更新対応の目標拘束添字の範囲だけを検証すると、別のスキン頂点から同じ目標拘束を指す2件が通り、目標の確定の2つのスレッドが同じ目標位置へ同時に書く。
// 別の目標拘束を指す2件は通る。
#[test]
fn 同じ目標拘束を指す更新対応の2件目を拒み別の目標拘束を指す2件は通す() {
    assert!(matches!(
        布素材::生成する(更新対応を据えた材料(&[(1, 0), (0, 5), (1, 7)])),
        Err(布素材エラー::目標の更新対応の拘束添字が重複 {
            先の対応番号: 0,
            後の対応番号: 2,
            添字
        }) if 添字 == 布の目標拘束添字::生成する(1)
    ));
    assert!(布素材::生成する(更新対応を据えた材料(&[(1, 0), (0, 5)])).is_ok());
}
