//! レンダラー生成に必要なシェーダーの束。個別引数の列挙をやめ、シェーダーの追加
//! (M7の明るさの圧縮等)で公開APIのシグネチャが伸び続けることを防ぐ(判断38)。

use crate::cloth_shader_set::布シェーダー一式;
use crate::compute_shader::コンピュートシェーダー;
use crate::distant_environment::遠方環境のシェーダー一式;
use crate::particle_shader_set::粒子シェーダー一式;
use crate::shader_set::シェーダー一式;

/// 大気のベイク済み画像を焼くコンピュートシェーダー。フレーム構成に空段階があるときだけパイプラインが作られる。
/// ベイク済み画像の枚数ぶんのエントリを1つの束にするのは、生成の順序と依存が枚数の間で決まっており、
/// 一部だけを差し替えられる状態を作らないためである。
#[derive(Debug, Clone)]
pub struct 大気のベイク済み画像のシェーダー一式 {
    pub 透過率: コンピュートシェーダー,
    pub 多重散乱: コンピュートシェーダー,
    pub スカイビュー: コンピュートシェーダー,
    pub 空中遠近: コンピュートシェーダー,
}

/// 空パスと空中遠近合成のシェーダー。空の放射輝度はプリコンピュート大気のベイク済み画像を参照して求める唯一の方式であり、
/// 画素ごとの方式分岐を持たない(参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「空の方式」)。
#[derive(Debug, Clone)]
pub struct 空シェーダー {
    /// スカイビューのベイク済み画像と透過率のベイク済み画像を追加のディスクリプタセットから参照し、放射輝度を評価する画素段。
    pub 放射輝度: シェーダー一式,
    /// 空中遠近の全画面合成。`None`は起動指定で合成を切った状態であり、遠景の霞が1画素も乗らない絵になる。
    pub 空中遠近合成: Option<シェーダー一式>,
}

/// レンダラーが使う全シェーダー。各フィールドはビルド時にslangcでコンパイル済みのSPIR-V。
#[derive(Debug, Clone)]
pub struct シェーダー束 {
    pub シーン: シェーダー一式,
    pub シャドウ: シェーダー一式,
    /// 空パスの全画面三角形と放射輝度評価。フレーム構成に空段階があるときだけパイプラインが作られる。
    pub 空: 空シェーダー,
    /// 大気のベイク済み画像の生成。フレーム構成に空段階があるときだけパイプラインが作られる。
    pub 大気のベイク済み画像: 大気のベイク済み画像のシェーダー一式,
    /// 遠方環境と派生表現の生成。照明問い合わせ契約が遠方環境の枝のときだけパイプラインが作られる。
    /// 契約に関わらず常に受け取るのは、束の有無をもう1つの一致条件にすると、契約と束と資源の3つを突き合わせることになるためである。
    pub 遠方環境: 遠方環境のシェーダー一式,
    pub 明るさの圧縮: シェーダー一式,
    /// 光のにじみピラミッドの前処理(判断41)。HDRからKaris平均+ソフト閾値で1/2解像度へ抽出する。
    pub 光のにじみ前処理: シェーダー一式,
    /// 光のにじみピラミッドの縮小(判断41)。13タップ縮小で1/2ずつ小さくする。
    pub 光のにじみ縮小: シェーダー一式,
    /// 光のにじみピラミッドの拡大(判断41)。3x3テントで広げて1段大きい縮小結果へ加算する。
    pub 光のにじみ拡大: シェーダー一式,
    pub ui: シェーダー一式,
    /// GPUスキニングのコンピュートシェーダー(判断44)。スキン付きシーンのときのみ使われる。
    pub スキニング: コンピュートシェーダー,
    /// 布シミュレーション一式(判断54)。布付き起動のときのみ使われる。
    pub 布: 布シェーダー一式,
    /// `--particles`指定時のみ`Some`(判断29)。
    pub 粒子: Option<粒子シェーダー一式>,
}
