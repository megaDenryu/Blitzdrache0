//! レンダラー生成に必要なシェーダーの束。個別引数の列挙をやめ、シェーダーの追加
//! (M7の明るさの圧縮等)で公開APIのシグネチャが伸び続けることを防ぐ(判断38)。

use crate::auto_exposure::自動露出のシェーダー一式;
use crate::cloth_shader_set::布シェーダー一式;
use crate::compute_shader::コンピュートシェーダー;
use crate::distant_environment::遠方環境のシェーダー一式;
use crate::indirect_lighting::契約別のシーン描画シェーダー;
use crate::local_visibility::局所可視性のシェーダー一式;
use crate::particle_shader_set::粒子シェーダー一式;
use crate::shader_set::シェーダー一式;
use crate::temporal_reconstruction::時間再構成のシェーダー一式;

/// 大気のベイク済み画像を焼くコンピュートシェーダー。フレーム構成に空段階があるときだけパイプラインが作られる。
/// ベイク済み画像の枚数ぶんのエントリを1つの束にするのは、生成の順序と依存が枚数の間で決まっており、
/// 一部だけを差し替えられる状態を作らないためである。
#[derive(Debug, Clone)]
pub struct 大気のベイク済み画像のシェーダー一式 {
    pub 透過率: コンピュートシェーダー,
    pub 多重散乱: コンピュートシェーダー,
    pub スカイビュー: コンピュートシェーダー,
    pub 空中遠近: コンピュートシェーダー,
}

/// 空パスと空中遠近合成のシェーダー。空の放射輝度はプリコンピュート大気のベイク済み画像を参照して求める唯一の方式であり、
/// 画素ごとの方式分岐を持たない(参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「空の方式」)。
/// `放射輝度`はスカイビューのベイク済み画像と透過率のベイク済み画像を追加のディスクリプタセットから参照する。
/// `空中遠近合成`の`None`は起動指定で合成を切った状態であり、遠景の霞が1画素も乗らない絵になる。
#[derive(Debug, Clone)]
pub struct 空シェーダー {
    pub 放射輝度: シェーダー一式,             // 放射輝度を評価する画素段
    pub 空中遠近合成: Option<シェーダー一式>, // 空中遠近の全画面合成
}

/// レンダラーが使う全シェーダー。各フィールドはビルド時にslangcでコンパイル済みのSPIR-Vである。
///
/// `シーン`の頂点段は照明問い合わせ契約の両方が同じものを持つ。`点光源の影`は可視ID列を参照せず、面のライト
/// ビュー射影をプッシュ定数で受け取る点が多段影と違う。影を落とす灯を1件も持たない世界でもパイプラインは作る。
/// 灯の宣言は毎フレームの入力であり、パイプラインの有無をそこへ連動させると宣言が変わるたびに資源の作り直しが
/// 要るためである。
///
/// `空`と`大気のベイク済み画像`のパイプラインは、フレーム構成に空段階があるときだけ作られる。`遠方環境`の
/// パイプラインは照明問い合わせ契約が遠方環境の枝のときだけ作られるが、束そのものは契約に関わらず常に受け取る。
/// 束の有無をもう1つの一致条件にすると、契約と束と資源の3つを突き合わせることになるためである。
/// `自動露出`・`局所可視性`・`時間再構成`は露出方式・拡散間接方式・時間再構成方式を実行時に世界が宣言するため、
/// `クラスタ選別`は全世界がこの経路を通るため、いずれも契約に関わらず常に受け取る。
///
/// 光のにじみピラミッド(判断41)は、`光のにじみ前処理`がHDRからKaris平均とソフト閾値で1/2解像度へ抽出し、
/// `光のにじみ縮小`が13タップ縮小で1/2ずつ小さくし、`光のにじみ拡大`が3x3テントで広げて1段大きい縮小結果へ
/// 加算する。`スキニング`はスキン付きシーンのときのみ使われる。
#[derive(Debug, Clone)]
pub struct シェーダー束 {
    pub シーン: 契約別のシーン描画シェーダー, // シーン描画。画素段は照明問い合わせ契約ごとに分かれる
    pub シャドウ: シェーダー一式,
    pub 点光源の影: シェーダー一式,                                 // 点光源の影の面ごとの記録
    pub 空: 空シェーダー,                                           // 空パスの全画面三角形と放射輝度評価
    pub 大気のベイク済み画像: 大気のベイク済み画像のシェーダー一式, // 大気のベイク済み画像の生成
    pub 遠方環境: 遠方環境のシェーダー一式,                         // 遠方環境と派生表現の生成
    pub 明るさの圧縮: シェーダー一式,
    pub 自動露出: 自動露出のシェーダー一式,     // 自動露出の集計と導出
    pub 局所可視性: 局所可視性のシェーダー一式, // 局所可視性補正の遮蔽の標本化と両側ぼかし
    pub クラスタ選別: コンピュートシェーダー,   // クラスタ格子のセルへ局所光を割り当てる選別のコンピュート
    pub 時間再構成: 時間再構成のシェーダー一式, // 時間再構成の全画面三角形
    pub 光のにじみ前処理: シェーダー一式,       // 光のにじみピラミッドの前処理
    pub 光のにじみ縮小: シェーダー一式,         // 同じピラミッドの縮小
    pub 光のにじみ拡大: シェーダー一式,         // 同じピラミッドの拡大
    pub ui: シェーダー一式,
    pub スキニング: コンピュートシェーダー, // GPUスキニングのコンピュートシェーダー(判断44)
    pub 布: 布シェーダー一式,               // 布シミュレーション一式(判断54)。布付き起動のときのみ使われる
    pub 粒子: Option<粒子シェーダー一式>,   // `--particles`指定時のみ`Some`(判断29)
}
