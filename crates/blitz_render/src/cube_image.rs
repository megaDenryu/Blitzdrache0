//! 立方体画像の面という概念と、面の中の位置と向きとの写像。ここにあるのは純粋な計算だけであり、
//! Vulkanの資源も、この面に何を焼くのかも知らない。
//!
//! 大気のベイク済み画像の下でなく独立した階層に置くのは、読み手が2つあるためである。1つは遠方環境と
//! 派生表現の立方体画像(`atmosphere`)であり、もう1つは点光源の影の立方体配列(`point_light_shadow`)である。
//! 面の並びと写像の正本が1つであることが、焼いた層と参照する層が食い違わないことの根拠であるから、
//! 読み手ごとに複製しない(1語1義。参照: CLAUDE.md「日本語命名の受理条件」)。
//!
//! 面の並びと軸の割り当てはVulkanの立方体画像の規約に固定する。写像の写しが`shaders/cube_face_mapping.slang`にあり、
//! 往復が恒等であることの検査はこの階層が持つ。

