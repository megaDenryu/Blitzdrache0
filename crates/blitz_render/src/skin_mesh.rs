//! スキンメッシュのGPU境界型(判断44)。頂点ごとのジョイント参照とウェイトを保持し、
//! スキニングコンピュートパスの入力になる。フレーム型・単位型を外した生の数値のみを持つ。

use thiserror::Error;

/// 1頂点ぶんのスキン属性。`repr(C)`でコンピュートシェーダーのstd430レイアウト
/// (uint4 16バイト + float4 16バイト)と一致させる。
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct スキン頂点属性 {
    pub ジョイント: [u32; 4],
    pub ウェイト: [f32; 4],
}

#[derive(Debug, Error, Clone, Copy, PartialEq, Eq)]
pub enum スキンメッシュ素材エラー {
    #[error("スキン属性が空だった")]
    属性が空,
    #[error("ジョイント数が0だった")]
    ジョイント数が0,
    #[error("頂点{頂点添字}のジョイント参照{参照}がジョイント数{ジョイント数}の範囲外だった")]
    ジョイント参照が範囲外 {
        頂点添字: usize, 参照: u32, ジョイント数: usize
    },
}

/// スキンメッシュ1つぶんの属性一覧とジョイント数。
/// 前提: 属性一覧の長さはレンダラー生成時に渡す頂点一覧と同じであること(生成側は検証できないため、レンダラー生成時に照合する)。
#[derive(Debug, Clone)]
pub struct スキンメッシュ素材 {
    属性一覧: Vec<スキン頂点属性>,
    ジョイント数: usize,
}

impl スキンメッシュ素材 {
    /// 属性が空でなく、全ジョイント参照が範囲内であることを検証して生成する。
    pub fn 生成する(属性一覧: Vec<スキン頂点属性>, ジョイント数: usize) -> Result<Self, スキンメッシュ素材エラー> {
        if 属性一覧.is_empty() {
            return Err(スキンメッシュ素材エラー::属性が空);
        }
        if ジョイント数 == 0 {
            return Err(スキンメッシュ素材エラー::ジョイント数が0);
        }
        for (頂点添字, 属性) in 属性一覧.iter().enumerate() {
            for &参照 in &属性.ジョイント {
                if usize::try_from(参照).map_or(true, |添字| 添字 >= ジョイント数) {
                    return Err(スキンメッシュ素材エラー::ジョイント参照が範囲外 {
                        頂点添字,
                        参照,
                        ジョイント数,
                    });
                }
            }
        }
        Ok(Self {
            属性一覧, ジョイント数
        })
    }

    pub(crate) fn 属性一覧(&self) -> &[スキン頂点属性] {
        &self.属性一覧
    }

    pub(crate) fn ジョイント数(&self) -> usize {
        self.ジョイント数
    }
}
