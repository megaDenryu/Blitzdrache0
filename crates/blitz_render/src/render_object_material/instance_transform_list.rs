//! 個体変換列: 1つの描画対象が1回の描画発行で描く個体の変換を、非空の一覧として持つ。
//! 通常メッシュと地形は1件だけの列になり、インスタンス群は個体数ぶんの列になる。レンダラーの仕事はどちらでも
//! 「列の件数だけインスタンスを描く」の1つであり、形状の種別で描画の手順が変わらない。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「描画発行」

use blitz_math::{ローカル, ワールド, 変換};

pub struct 個体変換列 {
    一覧: Vec<変換<ローカル, ワールド>>,
}

impl 個体変換列 {
    /// 先頭を別引数にすることで、個体を1つも持たない列を構築不能にする。
    pub fn 生成する(先頭: 変換<ローカル, ワールド>, 残り: Vec<変換<ローカル, ワールド>>) -> Self {
        let mut 一覧 = Vec::with_capacity(1 + 残り.len());
        一覧.push(先頭);
        一覧.extend(残り);
        Self { 一覧 }
    }

    pub(crate) fn 一覧(&self) -> &[変換<ローカル, ワールド>] {
        &self.一覧
    }

    pub fn 件数(&self) -> usize {
        self.一覧.len()
    }
}
