//! 材質スロット素材一覧: 1つの描画対象が材質スロットごとに与える材質の非空な一覧。
//! 材質を1つしか持たない対象も同じ型で表す。レンダラーの仕事はどちらでも「発行が指すスロットの材質を束縛する」の1つだけであり、
//! 材質の数で束縛の手順が変わらないためである。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「束縛バックエンドの移行境界」

use super::material_slot_entry::材質スロット素材;

pub struct 材質スロット素材一覧 {
    一覧: Vec<材質スロット素材>,
}

impl 材質スロット素材一覧 {
    pub fn 生成する(先頭: 材質スロット素材, 残り: Vec<材質スロット素材>) -> Self {
        let mut 一覧 = Vec::with_capacity(1 + 残り.len());
        一覧.push(先頭);
        一覧.extend(残り);
        Self { 一覧 }
    }

    pub fn 一覧(&self) -> &[材質スロット素材] {
        &self.一覧
    }

    pub fn 件数(&self) -> usize {
        self.一覧.len()
    }
}
