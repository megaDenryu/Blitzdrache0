//! 材質スロット素材: 1つの材質スロットへ与える材質と、そのスロットの番号。
//! 番号を並びの添字で代用しないのは、原型が未使用スロットを持つことを許す契約のもとで番号が飛びうるためである。
//! プリミティブ描画発行はこの番号で材質を指すため、番号と材質の対応が失われると描く材質を決められない。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「入力契約と実行時形式(scene v4、実装済み)」

use crate::material::マテリアル素材;

pub struct 材質スロット素材 {
    スロット番号: u32,
    マテリアル: マテリアル素材,
}

impl 材質スロット素材 {
    pub fn 生成する(スロット番号: u32, マテリアル: マテリアル素材) -> Self {
        Self {
            スロット番号, マテリアル
        }
    }

    pub fn スロット番号(&self) -> u32 {
        self.スロット番号
    }

    pub(crate) fn マテリアル(&self) -> &マテリアル素材 {
        &self.マテリアル
    }
}
