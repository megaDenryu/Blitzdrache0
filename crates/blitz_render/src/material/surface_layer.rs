//! 地表の層の重ね合わせをGPUへ渡す素材。担当するのは、塗り分けの重み1枚と層ごとのタイル4枚と層ごとのタイル倍率を、
//! 揃った1つの組として保つことである。
//!
//! テクスチャを`Option`で持たないのは、この枝が重みも層のタイルも必ず持つためである。1枚でも欠けた素材は描けず、
//! 「無し」は値の不在ではなく枝の不成立を意味する。層のタイルを結ぶのは実行時形式を読んだ後の変換の段であり、
//! そこが世界に1つの地表層テクスチャ集から4枚を引いてこの型を組む
//! (参照: `_doc/設計/マルチマテリアルと材質境界.md`「地表の層の重ね合わせ」)。

use super::layer_count::地表層の数;
use crate::pbr_material::マテリアル素材エラー;
use crate::texture_material::テクスチャ素材;
use crate::vulkan::material_table::材質テクスチャ役割;

#[derive(Debug, Clone)]
pub struct 地表の層の重ね合わせ素材 {
    重み: テクスチャ素材,
    層ごとのタイル: [テクスチャ素材; 地表層の数],
    層ごとのタイル倍率: [f32; 地表層の数],
    金属度係数: f32,
    粗さ係数: f32,
}

impl 地表の層の重ね合わせ素材 {
    pub fn 生成する(
        重み: テクスチャ素材,
        層ごとのタイル: [テクスチャ素材; 地表層の数],
        層ごとのタイル倍率: [f32; 地表層の数],
        金属度係数: f32,
        粗さ係数: f32,
    ) -> Result<Self, マテリアル素材エラー> {
        for 成分 in [金属度係数, 粗さ係数] {
            if !(0.0..=1.0).contains(&成分) {
                return Err(マテリアル素材エラー::係数範囲外(成分));
            }
        }
        for 倍率 in 層ごとのタイル倍率 {
            if !倍率.is_finite() || 倍率 <= 0.0 {
                return Err(マテリアル素材エラー::タイル倍率が正の有限値でない(倍率));
            }
        }
        Ok(Self {
            重み,
            層ごとのタイル,
            層ごとのタイル倍率,
            金属度係数,
            粗さ係数,
        })
    }

    /// 役割で1枚を引く。この枝が持たない役割が`None`になるのは、その材質がその役割のテクスチャを持たないという意味そのものである。
    pub(crate) fn 役割のテクスチャ(&self, 役割: 材質テクスチャ役割) -> Option<&テクスチャ素材> {
        match 役割 {
            材質テクスチャ役割::ベースカラー | 材質テクスチャ役割::金属粗さ | 材質テクスチャ役割::法線マップ => {
                None
            }
            材質テクスチャ役割::地表の層の重み => Some(&self.重み),
            材質テクスチャ役割::地表の層0のタイル => self.層ごとのタイル.first(),
            材質テクスチャ役割::地表の層1のタイル => self.層ごとのタイル.get(1),
            材質テクスチャ役割::地表の層2のタイル => self.層ごとのタイル.get(2),
            材質テクスチャ役割::地表の層3のタイル => self.層ごとのタイル.get(3),
        }
    }

    pub(crate) fn 層ごとのタイル倍率(&self) -> [f32; 地表層の数] {
        self.層ごとのタイル倍率
    }

    pub(crate) fn 金属度係数(&self) -> f32 {
        self.金属度係数
    }

    pub(crate) fn 粗さ係数(&self) -> f32 {
        self.粗さ係数
    }
}
