//! 1フレーム描画の結果を表す判別共用体。

/// `一フレーム描画する` が正常終了したときに返す結果。
/// 最小化中・再構築中の非描画はエラーでも無言スキップでもなく、この型で表す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 描画結果 {
    /// フレームを完成させ、スワップチェーンへ提示した。
    提示した,
    /// 提示可能な状態でなかったため、このフレームの描画を見送った。
    見送った(見送り理由),
}

/// 描画を見送った理由。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 見送り理由 {
    /// ウィンドウが最小化中で寸法が0のため、描画対象がない。
    最小化中,
    /// スワップチェーンが陳腐化しており、次フレームで再構築するため。
    スワップチェーン再構築中,
}
