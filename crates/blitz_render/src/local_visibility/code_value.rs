//! 局所可視度と、局所可視度画像がGPU上で取る8ビット無符号正規化形式の符号値との往復。
//! 触れる状態を持たず、担うのは画像形式の丸めの規約をただ1箇所へ置くことである。
//!
//! 形式を8ビット1成分に決めるのは、局所可視度が0以上1以下の1つの係数であり、両側ぼかしを通した後の
//! 256段階が拡散間接照度への乗数として絵に段差を出さないためである。16ビットにすると帯域が倍になり、
//! 得られる段階は絵に現れない。検収が許す誤差の「1符号値程度」はこの形式の1段のことである。
//!
//! 丸めを正本が持つのは、CPU正本とGPU出力を突き合わせる検収が、同じ規約で量子化した値どうしを比べる
//! ためである。丸め方が2つあると、写しの誤りと丸めの違いを見分けられない。

use crate::numeric::floor_index::実数位置の床の添字;

use super::visibility::局所可視度;

/// 8ビット無符号正規化形式が取りうる最大の符号値。
const 符号値の最大: u32 = 255;

/// 局所可視度を8ビット無符号正規化形式へ写した値。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 局所可視度の符号値 {
    値: u8,
}

impl 局所可視度の符号値 {
    /// 最も近い符号値へ丸める。ちょうど中間の値は明るい側(遮蔽の弱い側)へ寄せる。
    pub fn 量子化する(可視度: 局所可視度) -> Self {
        let 目盛の位置 = f64::from(可視度.値()) * f64::from(符号値の最大) + 0.5;
        let 符号値 = 実数位置の床の添字(目盛の位置, 符号値の最大);
        let 値 = u8::try_from(符号値).unwrap_or_else(|_| panic!("量子化した符号値{符号値}が8ビットに収まらない"));
        Self { 値 }
    }

    pub fn 値(self) -> u8 {
        self.値
    }

    /// 符号値が表す局所可視度。読み戻したGPUの画像をCPU正本と同じ土俵へ載せるために使う。
    pub fn 局所可視度へ戻す(self) -> 局所可視度 {
        let 最大 = f32::from(u8::MAX);
        局所可視度::生成する(f32::from(self.値) / 最大).unwrap_or_else(|誤り| panic!("符号値から局所可視度を作れない: {誤り}"))
    }
}
