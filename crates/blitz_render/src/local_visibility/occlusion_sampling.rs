//! 画素1つの局所可視度を求める工程。受け取るのは深度画像と射影と遮蔽の設定と画素の位置、返すのは局所可視度である。
//!
//! 標本を半球の面の上に置き、その点が深度画像の中で手前の面に隠れているかを数える。半球の内側へ距離を
//! 散らさないのは、散らす割合が設定の軸を1つ増やすためである。近い側の陰りが足りないとオーナーの目視が
//! 判じたときに距離の分布を足す余地は、標本の向きと距離が別の量である限り閉じていない。
//!
//! 深度が書かれていない画素と、法線の面が定まらない画素は遮蔽なしへ退避する。空の背景に陰りを描かないこと
//! そのものがこの退避である。

use blitz_math::{ビュー, メートル, 位置};

use super::depth_image::深度画像;
use super::hemisphere_sample::半球の標本の向きを求める;
use super::normal_reconstruction::{ビュー空間法線を再構成する, 法線の再構成結果};
use super::occlusion_settings::遮蔽の設定;
use super::projection::射影の復元;
use super::rotation::{標本の回転, 画素位置から回転を選ぶ};
use super::view_direction::ビュー空間の向き;
use super::view_displacement::ビュー空間の変位;
use super::view_position::{
    カメラからの奥行き, 位置が落ちる画素を求める, 画素が覆う幅を求める, 画素中心の位置を復元する
};
use super::visibility::局所可視度;

/// 標本を撒く起点。標点の位置と法線と回転、そして標点の奥行きで決めた奥行きの差の下限を持つ。
/// 4つを1組にするのは、どれも画素1つにつき1度だけ決まり、標本ごとには変わらないためである。
/// 奥行きの差の下限を標本ごとに決め直さないのは、標本が半径の内側にあり、その範囲で1画素が覆う幅が
/// ほとんど変わらないためである。
#[derive(Debug, Clone, Copy)]
struct 標本を撒く起点 {
    標点: 位置<ビュー>,
    法線: ビュー空間の向き,
    回転: 標本の回転,
    奥行きの差の下限: メートル,
}

/// 画素1つの局所可視度。
/// 前提: 呼び出し元は画素が寸法の内側にあることを確かめている。
pub fn 画素の局所可視度を求める(
    深度画像: &深度画像, 射影: 射影の復元, 設定: 遮蔽の設定, 横: u32, 縦: u32
) -> 局所可視度 {
    if !深度画像.ジオメトリがあるか(横, 縦) {
        return 局所可視度::遮蔽なし();
    }
    let 標点 = 画素中心の位置を復元する(射影, 深度画像.寸法(), 横, 縦, 深度画像.深度(横, 縦));
    let 法線の再構成結果::再構成できた(法線) = ビュー空間法線を再構成する(深度画像, 射影, 設定.同一面の許容(), 横, 縦)
    else {
        return 局所可視度::遮蔽なし();
    };
    let 覆う幅 = 画素が覆う幅を求める(射影, 深度画像.寸法(), カメラからの奥行き(標点));
    let 起点 = 標本を撒く起点 {
        標点,
        法線,
        回転: 画素位置から回転を選ぶ(横, 縦),
        奥行きの差の下限: 設定.深度バイアス().奥行きの差の下限(覆う幅),
    };
    let mut 重みの和 = 0.0_f32;
    for 添字 in 0..設定.標本数().値() {
        重みの和 += 標本の遮蔽の重み(深度画像, 射影, 設定, 起点, 添字);
    }
    局所可視度::遮蔽の割合から求める(重みの和 * 設定.標本数().標本1件の重み())
}

/// 標本1本が遮蔽へ寄与する重み。遮蔽していない標本と、画面の外や空へ落ちた標本は0を返す。
fn 標本の遮蔽の重み(
    深度画像: &深度画像, 射影: 射影の復元, 設定: 遮蔽の設定, 起点: 標本を撒く起点, 添字: u32
) -> f32 {
    let 標点 = 起点.標点;
    let 向き = 半球の標本の向きを求める(添字, 設定.標本数(), 起点.回転, 起点.法線);
    let 標本点 = ビュー空間の変位::向きと長さから(向き, 設定.半径().長さ()).位置へ足す(標点);
    let Some((標本の横, 標本の縦)) = 位置が落ちる画素を求める(射影, 深度画像.寸法(), 標本点) else {
        return 0.0;
    };
    if !深度画像.ジオメトリがあるか(標本の横, 標本の縦) {
        return 0.0;
    }
    let 遮蔽点 = 画素中心の位置を復元する(射影, 深度画像.寸法(), 標本の横, 標本の縦, 深度画像.深度(標本の横, 標本の縦));
    let 遮蔽点の奥行き = カメラからの奥行き(遮蔽点);
    if 遮蔽点の奥行き.値() + 起点.奥行きの差の下限.値() >= カメラからの奥行き(標本点).値() {
        return 0.0;
    }
    設定.距離減衰().重みを求める(設定.半径(), 遮蔽点の奥行き - カメラからの奥行き(標点))
}
