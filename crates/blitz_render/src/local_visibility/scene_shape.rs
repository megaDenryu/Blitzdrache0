//! 検収が焼ける形の語彙。触れる状態を持たず、担うのは形ごとの寸法の並びを1つの判別共用体で表すことだけである。
//!
//! 値域を確かめる生成の入口(`synthetic_scene`)と、形ごとの解析解を持つ交わりの工程(`scene_intersection`)の
//! 2つがこの語彙を共有する。生成の側へ置くと交わりの工程が生成の入口の実装詳細へ依存し、交わりの側へ置くと
//! 生成の入口が解析解の実装詳細へ依存する。どちらでもない置き場としてここへ分ける。

use blitz_math::{メートル, 逆メートル};

/// 形ごとの寸法。値域は生成の入口が確かめている。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) enum 場面の形 {
    平面 {
        中心の奥行き: メートル,
        横の傾き: f32,
    },
    段差 {
        手前の奥行き: メートル,
        奥の奥行き: メートル,
        境界の横位置: u32,
    },
    球 {
        中心の奥行き: メートル,
        半径: メートル,
    },
    凹面 {
        底の奥行き: メートル,
        曲率: 逆メートル,
    },
}
