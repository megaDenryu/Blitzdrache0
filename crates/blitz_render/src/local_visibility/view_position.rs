//! 画素の位置とビュー空間の位置を往復する工程。受け取るのは射影と寸法と画素または位置、返すのは
//! 復元したビュー空間の位置、または位置が落ちる画素である。
//!
//! 往復の2方向を1つのファイルへ置くのは、どちらも同じ1つの規約(画素の中心が正規化装置座標のどこに当たるか)を
//! 使うためである。片方だけを直すと標本が半画素ずれ、平坦な面へ縞が出る。
//!
//! 画面の外へ落ちた位置は値なしを返す。範囲へ張り付けて読むと、画面端の画素が端の1列を何度も遮蔽物として
//! 数え、画面の縁に暗い帯が出るためである。

use blitz_math::{ビュー, メートル, 位置};

use crate::numeric::floor_index::実数位置の床の添字;

use super::image_size::画像の寸法;
use super::narrowing::整数を単精度へ狭める;
use super::projection::射影の復元;

/// カメラから見た奥行き。ビュー空間では視線が奥行きの負の向きであるため、符号を反転した値が距離になる。
pub fn カメラからの奥行き(場所: 位置<ビュー>) -> メートル {
    メートル::生成する(-場所.z().値())
}

/// その奥行きで1画素が覆うビュー空間の幅。縦と横で違う場合は広い側を採る。
/// 深度が画素の中心でしか標本化されないことによる誤差の大きさがこの幅であり、遮蔽の判定の下限と
/// 同じ面と認める距離の上限がこれを基準にする。
pub fn 画素が覆う幅を求める(射影: 射影の復元, 寸法: 画像の寸法, 奥行き: メートル) -> メートル {
    let 縦の幅 = 2.0 * 射影.縦視野角の半角の正接() * 奥行き.値() / 整数を単精度へ狭める(寸法.高さ());
    let 横の幅 = 縦の幅 * 射影.横縦比() * 整数を単精度へ狭める(寸法.高さ()) / 整数を単精度へ狭める(寸法.幅());
    メートル::生成する(縦の幅.max(横の幅))
}

/// 画素の中心と深度が指すビュー空間の位置。
/// 前提: 呼び出し元は画素が寸法の内側にあることを確かめている。
pub fn 画素中心の位置を復元する(射影: 射影の復元, 寸法: 画像の寸法, 横: u32, 縦: u32, 深度: f32) -> 位置<ビュー> {
    let 奥行き = 射影.奥行きを復元する(深度);
    let [正規化横, 正規化縦] = 画素中心の正規化装置座標(寸法, 横, 縦);
    let 横位置 = 正規化横 * 射影.縦視野角の半角の正接() * 射影.横縦比() * 奥行き.値();
    let 縦位置 = -正規化縦 * 射影.縦視野角の半角の正接() * 奥行き.値();
    位置::生成する(メートル::生成する(横位置), メートル::生成する(縦位置), メートル::生成する(-奥行き.値()))
}

/// その位置が落ちる画素。近クリップ面より手前にある位置と、画面の外へ落ちた位置は値なしになる。
pub fn 位置が落ちる画素を求める(射影: 射影の復元, 寸法: 画像の寸法, 場所: 位置<ビュー>) -> Option<(u32, u32)> {
    let 奥行き = カメラからの奥行き(場所).値();
    if !奥行き.is_finite() || 奥行き < 射影.近クリップ().値() {
        return None;
    }
    let 正規化横 = 場所.x().値() / (射影.縦視野角の半角の正接() * 射影.横縦比() * 奥行き);
    let 正規化縦 = -場所.y().値() / (射影.縦視野角の半角の正接() * 奥行き);
    let 横実数 = (f64::from(正規化横) + 1.0) * 0.5 * f64::from(寸法.幅());
    let 縦実数 = (f64::from(正規化縦) + 1.0) * 0.5 * f64::from(寸法.高さ());
    let 横 = 画素の位置へ落とす(横実数, 寸法.幅())?;
    let 縦 = 画素の位置へ落とす(縦実数, 寸法.高さ())?;
    Some((横, 縦))
}

/// 画素の中心が正規化装置座標のどこに当たるか。横は右が正、縦は下が正である。
pub(super) fn 画素中心の正規化装置座標(寸法: 画像の寸法, 横: u32, 縦: u32) -> [f32; 2] {
    let 正規化横 = 2.0 * (f64::from(横) + 0.5) / f64::from(寸法.幅()) - 1.0;
    let 正規化縦 = 2.0 * (f64::from(縦) + 0.5) / f64::from(寸法.高さ()) - 1.0;
    [super::narrowing::単精度へ狭める(正規化横), super::narrowing::単精度へ狭める(正規化縦)]
}

/// 画素の中心を原点に0.5足した実数位置から画素の位置を求める。範囲の外は値なしである。
fn 画素の位置へ落とす(実数位置: f64, 画素数: u32) -> Option<u32> {
    if !実数位置.is_finite() || 実数位置 < 0.0 || 実数位置 >= f64::from(画素数) {
        return None;
    }
    Some(実数位置の床の添字(実数位置, 画素数 - 1))
}
