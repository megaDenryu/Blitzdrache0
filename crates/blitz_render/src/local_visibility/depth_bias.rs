//! 遮蔽と判定するために要る奥行きの差の下限を、その奥行きで1画素が覆う幅に対する倍率で表した量そのもの。
//! 触れる状態を持たず、担うのは値域の保証と、覆う幅から実際の下限を導くことだけである。
//!
//! この量が要るのは、標点の載る面そのものが標本の背後に僅かに現れるためである。深度は画素の中心でしか
//! 標本化されないため、傾いた面では隣の画素の面が標本より手前に来ることがあり、下限を置かないと
//! 平坦な面が自分自身を遮蔽して縞が出る。
//!
//! 絶対の長さで持たないのは、この誤差の大きさが1画素の覆う幅に比例するためである。絶対値で持つと、
//! 近くでは陰りが消えるほど大きく、遠くでは縞が出るほど小さい下限が同時に起きる。

use blitz_math::メートル;

use super::error::局所可視性エラー;

/// 遮蔽物が標本より手前にあると認めるために要る奥行きの差の下限を、1画素が覆う幅への倍率で表した値。
/// 不変条件: 有限かつ0以上である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 遮蔽の深度バイアス {
    倍率: f32,
}

impl 遮蔽の深度バイアス {
    pub fn 生成する(倍率: f32) -> Result<Self, 局所可視性エラー> {
        if !倍率.is_finite() || 倍率 < 0.0 {
            return Err(局所可視性エラー::値域外("遮蔽の深度バイアスの倍率", 倍率));
        }
        Ok(Self { 倍率 })
    }

    pub fn 倍率(self) -> f32 {
        self.倍率
    }

    /// その奥行きでの奥行きの差の下限。
    pub fn 奥行きの差の下限(self, 画素が覆う幅: メートル) -> メートル {
        メートル::生成する(画素が覆う幅.値() * self.倍率)
    }
}
