//! 2つの点が同じ面に載っていると認める距離の上限を、その奥行きで1画素が覆う幅に対する倍率で表した量そのもの。
//! 触れる状態を持たず、担うのは値域の保証と、覆う幅から実際の上限を導くことだけである。
//!
//! 絶対の長さでも奥行きに対する比でもなく、1画素が覆う幅への倍率で持つ。深度が画素の中心でしか標本化されない
//! ことがこの判定の誤差の出どころであり、その誤差の大きさは覆う幅そのものだからである。奥行きに対する比で持つと、
//! 同じ設定が画面の縦の画素数で意味を変える(覆う幅は縦の画素数に反比例する)。
//!
//! 倍率が1より大きいことを要求するのは、隣り合う画素は正対する面の上でも1つぶんは離れているためである。
//! 1以下では平らな面が常に別の面と判定される。

use blitz_math::メートル;

use super::error::局所可視性エラー;

/// 同じ面に載っていると認める距離の上限を、1画素が覆う幅への倍率で表した値。
/// 不変条件: 有限かつ1より大きい。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 同一面の許容倍率 {
    値: f32,
}

impl 同一面の許容倍率 {
    pub fn 生成する(値: f32) -> Result<Self, 局所可視性エラー> {
        if !値.is_finite() || 値 <= 1.0 {
            return Err(局所可視性エラー::値域外("同一面の許容倍率", 値));
        }
        Ok(Self { 値 })
    }

    pub fn 値(self) -> f32 {
        self.値
    }

    /// その奥行きで、同じ面に載っていると認める距離の上限。
    pub fn 距離の上限(self, 画素が覆う幅: メートル) -> メートル {
        メートル::生成する(画素が覆う幅.値() * self.値)
    }
}
