//! 標本の方位を画素ごとにずらす回転。触れる状態を持たず、担うのは有限個の回転を番号から作ることと、
//! 画素の位置から1つを選ぶこと、そして接空間の方位をその角だけ回すことである。
//!
//! 回転を画素ごとに変えるのは、全画素で同じ方位を使うと少ない標本数の偏りが同じ形の帯として画面へ
//! 焼き付くためである。連続な角でなく有限個から選ぶのは、両側ぼかしの窓が本数ぶんの向きを均せる
//! 広さであることを設定として言えるようにするためである。
//!
//! 番号から角を作る余弦と正弦は超越関数を通るが、入力が定数の角であるため機材ごとの近似の差は
//! 最下位のビットに留まる。禁じているのは、画素ごとに違う値を正弦へ入れて雑音を作る混ぜ方である。

use std::f64::consts::TAU;

use super::narrowing::単精度へ狭める;
use super::pixel_hash::画素位置の整数ハッシュ;

/// 用意する回転の本数。両側ぼかしの既定の窓(5画素四方の25画素)がこの本数を覆える広さである。
pub const 標本の回転の本数: u32 = 16;

/// 接空間の方位を回す1つの回転。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 標本の回転 {
    余弦: f32,
    正弦: f32,
}

impl 標本の回転 {
    /// 番号が表す回転。全周を本数で等分した角を割り当てる。
    /// 前提: 番号は本数未満である(呼び出し元が剰余で丸める)。
    pub fn 番号から作る(番号: u32) -> Self {
        let 角 = TAU * f64::from(番号) / f64::from(標本の回転の本数);
        Self {
            余弦: 単精度へ狭める(角.cos()),
            正弦: 単精度へ狭める(角.sin()),
        }
    }

    pub fn 余弦(self) -> f32 {
        self.余弦
    }

    pub fn 正弦(self) -> f32 {
        self.正弦
    }

    /// 接空間の平面の向きをこの回転の角だけ回した向き。
    pub fn 平面の向きを回す(self, 向き: [f32; 2]) -> [f32; 2] {
        [向き[0] * self.余弦 - 向き[1] * self.正弦, 向き[0] * self.正弦 + 向き[1] * self.余弦]
    }
}

/// その画素が使う回転。同じ位置なら必ず同じ回転を返す。
pub fn 画素位置から回転を選ぶ(横: u32, 縦: u32) -> 標本の回転 {
    標本の回転::番号から作る(画素位置の整数ハッシュ(横, 縦) % 標本の回転の本数)
}

/// 回転の番号がすべて別の向きを指すことを、番号から作る角の余弦と正弦の組で表した一覧。
pub fn 全回転() -> impl Iterator<Item = 標本の回転> {
    (0..標本の回転の本数).map(標本の回転::番号から作る)
}
