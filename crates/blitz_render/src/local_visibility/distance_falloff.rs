//! 標点と遮蔽物の奥行きの差が広がるにつれて遮蔽の重みを下げる規則。触れる状態を持たず、担うのは
//! 2つの倍率の値域の保証と、差から重みを導くことだけである。
//!
//! この規則が要るのは、画面空間の標本が「標本より手前にある面」をすべて遮蔽物として数えてしまうためである。
//! 遠くの標点の前を近くの物体が横切ると、実際には触れていない面が暗くなる。差が半径の何倍まで遮蔽として
//! 数えるかをここで断ち切る。
//!
//! 断ち切りを段でなく滑らかにするのは、重みが跳ぶと物体の輪郭に沿って濃さの段差が出るためである。

use blitz_math::メートル;

use super::error::局所可視性エラー;
use super::occlusion_radius::遮蔽半径;

/// 奥行きの差から遮蔽の重みを導く規則。倍率はどちらも遮蔽半径に対する比である。
/// 不変条件: 2つの倍率は有限で、重みを保つ倍率が0以上、重みが尽きる倍率がそれより大きい。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 遮蔽の距離減衰 {
    重みを保つ倍率: f32,
    重みが尽きる倍率: f32,
}

impl 遮蔽の距離減衰 {
    pub fn 生成する(重みを保つ倍率: f32, 重みが尽きる倍率: f32) -> Result<Self, 局所可視性エラー> {
        if !重みを保つ倍率.is_finite() || 重みを保つ倍率 < 0.0 {
            return Err(局所可視性エラー::値域外("重みを保つ倍率", 重みを保つ倍率));
        }
        if !重みが尽きる倍率.is_finite() || 重みが尽きる倍率 <= 重みを保つ倍率 {
            return Err(局所可視性エラー::上下の順序が逆(
                "遮蔽の距離減衰の倍率",
                重みを保つ倍率,
                重みが尽きる倍率,
            ));
        }
        Ok(Self {
            重みを保つ倍率,
            重みが尽きる倍率,
        })
    }

    pub fn 重みを保つ倍率(self) -> f32 {
        self.重みを保つ倍率
    }

    pub fn 重みが尽きる倍率(self) -> f32 {
        self.重みが尽きる倍率
    }

    /// 遮蔽物と標点の奥行きの差に対する遮蔽の重み。差が小さいうちは1、尽きる距離を越えると0であり、
    /// 間は両端で傾きが0になる三次の曲線でつなぐ。
    pub fn 重みを求める(self, 半径: 遮蔽半径, 奥行きの差: メートル) -> f32 {
        let 差 = 奥行きの差.値().abs();
        let 保つ距離 = 半径.長さ().値() * self.重みを保つ倍率;
        let 尽きる距離 = 半径.長さ().値() * self.重みが尽きる倍率;
        if !差.is_finite() || 差 >= 尽きる距離 {
            return 0.0;
        }
        if 差 <= 保つ距離 {
            return 1.0;
        }
        let 進み = (差 - 保つ距離) / (尽きる距離 - 保つ距離);
        1.0 - 進み * 進み * (3.0 - 2.0 * 進み)
    }
}
