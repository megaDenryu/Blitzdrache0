//! 標本1本ぶんの向きを求める工程。受け取るのは標本の添字と本数とその画素の回転と法線、返すのは
//! 法線を軸とする半球の面の上のビュー空間の向きである。
//!
//! ハンマーズリー列と接基底は派生表現の畳み込みが持つ正本を共有する。同じ数学へ2つの正本を置くと、
//! シェーダー側の写しも2本になり、値の一致検査が二重になるためである。
//!
//! 平面の長さを第二成分の平方根に取ると、向きの分布は法線との余弦に比例する。標本を法線の近くへ厚く置く
//! この分布は、余弦を掛けて積分する拡散間接の遮蔽の形と合っており、同じ標本数でむらが小さい。

use std::f64::consts::TAU;

use crate::distant_environment::derived::{ハンマーズリー標本を求める, 接基底の向きを戻す, 接基底を組む};

use super::narrowing::単精度へ狭める;
use super::rotation::標本の回転;
use super::sample_count::遮蔽の標本数;
use super::view_direction::ビュー空間の向き;

/// 半球の面の上の標本の向き。返す向きと法線の内積は必ず0以上である。
/// 前提: 添字は標本数未満である。
pub fn 半球の標本の向きを求める(
    添字: u32, 標本数: 遮蔽の標本数, 回転: 標本の回転, 法線: ビュー空間の向き
) -> ビュー空間の向き {
    let [方位の割合, 高さの割合] = ハンマーズリー標本を求める(添字, 標本数.値());
    let 平面の長さ = 単精度へ狭める(高さの割合.sqrt());
    let 法線方向の長さ = 単精度へ狭める((1.0 - 高さの割合).sqrt());
    let 方位角 = TAU * 方位の割合;
    let 回した = 回転.平面の向きを回す([単精度へ狭める(方位角.cos()), 単精度へ狭める(方位角.sin())]);
    let 接空間の向き = [平面の長さ * 回した[0], 平面の長さ * 回した[1], 法線方向の長さ];
    接空間から戻す(法線, 接空間の向き)
}

/// 接空間の座標で表した向きを、法線を第三軸とする基底でビュー空間へ戻す。
fn 接空間から戻す(法線: ビュー空間の向き, 接空間の向き: [f32; 3]) -> ビュー空間の向き {
    let 法線の倍精度 = 法線.成分().map(f64::from);
    let 基底 = 接基底を組む(法線の倍精度);
    let 戻した = 接基底の向きを戻す(基底, 法線の倍精度, 接空間の向き.map(f64::from));
    let 成分 = [単精度へ狭める(戻した[0]), 単精度へ狭める(戻した[1]), 単精度へ狭める(戻した[2])];
    ビュー空間の向き::生成する(成分).unwrap_or_else(|誤り| panic!("正規直交な基底から単位でない標本の向きが出た: {誤り}"))
}
