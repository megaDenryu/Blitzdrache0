//! 1画素あたりに置く遮蔽の標本の本数という量そのもの。触れる状態を持たず、担うのは値域の保証と、
//! 標本1件あたりの重みを与えることだけである。
//!
//! 上限を置くのは、標本数が画素あたりの費用にそのまま比例し、桁を誤った設定が絵でなく実行時間として
//! しか現れないためである。上限そのものに物理的な意味は無く、誤りを早く止めるための柵である。

use super::error::局所可視性エラー;
use super::narrowing::整数を単精度へ狭める;

/// 誤った桁の設定を止めるための本数の上限。
const 標本数の上限: u32 = 1024;

/// 1画素あたりに置く遮蔽の標本の本数。
/// 不変条件: 1以上、標本数の上限以下である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 遮蔽の標本数 {
    値: u32,
}

impl 遮蔽の標本数 {
    pub fn 生成する(値: u32) -> Result<Self, 局所可視性エラー> {
        if 値 == 0 || 値 > 標本数の上限 {
            return Err(局所可視性エラー::整数値域外("遮蔽の標本数", 値));
        }
        Ok(Self { 値 })
    }

    pub fn 値(self) -> u32 {
        self.値
    }

    /// 標本1件が遮蔽の割合へ寄与しうる最大の重み。全件が遮蔽なら割合はちょうど1になる。
    pub fn 標本1件の重み(self) -> f32 {
        1.0 / 整数を単精度へ狭める(self.値)
    }
}
