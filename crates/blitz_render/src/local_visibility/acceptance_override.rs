//! 検収が局所可視度を既知の一定値へ固定する上書き。触れる状態を持たず、担うのは「上書きしない」と
//! 「この符号値で埋める」の2つを1つの判別共用体で表すことだけである。
//!
//! これが要るのは、局所可視度が拡散間接照度だけへ掛かることを画素の値で反証するためである。可視度を全画面で
//! 0と1に固定した2枚を比べると、変わってよいのは拡散間接の項だけであり、直接光と鏡面間接を掛けている
//! 実装ではそれ以外の画素も動く。深度から焼いた可視度では画素ごとに値が違うため、この比較が成立しない。
//!
//! 真偽値2つ(上書きするか・その値)で持たないのは、上書きしないときの値が意味を持たないためである。
//! 消す値をどこかに置くと、上書きの判定を忘れた消費側がその値を掛けてしまう。
//!
//! 上書きした実行は遮蔽の標本化も両側ぼかしも1本も積まない。積むと2枚が上書きの値から書き換わり、
//! 固定したはずの可視度が画素ごとに違う値へ戻る。

use super::code_value::局所可視度の符号値;

/// 検収が局所可視度へ掛ける上書き。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 局所可視度の上書き {
    /// 既定。深度から焼いた可視度をそのまま使う。
    上書きしない,
    /// 全画素をこの符号値で埋め、2本のパスを1本も積まない。
    固定符号値(局所可視度の符号値),
}
