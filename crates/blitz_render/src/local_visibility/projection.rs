//! 深度と画素の位置からビュー空間の量を復元するために要る射影の情報。触れる状態を持たず、担うのは
//! 値域の保証と、深度と奥行きの往復という1つの規約を持つことである。
//!
//! 逆行列でなく4つの量で持つのは、この復元がカメラの透視投影に限られ、行列の一般の逆を必要としないためである。
//! 4つの量なら不変条件(近が正で遠より手前、視野角が開いている)を型が守れるが、行列では守れない。
//!
//! 深度の規約はVulkanのクリップ空間そのものであり、0が近クリップ面、1が遠クリップ面である
//! (`crates/blitz_math/src/frame/transform_construct.rs`の透視投影が正本)。

use blitz_math::{メートル, ラジアン, 画素内ずらし};

use super::error::局所可視性エラー;

/// 透視投影の逆変換に要る4つの量と、その深度を書いた射影が受けた画素内ずらし。
/// ずらしを持つのは、深度を書いた射影と位置を戻す射影が同じでなければ原理が合わないためである
/// (参照: `_doc/設計/時間再構成.md`「判断a」)。
/// 不変条件: 近クリップは有限かつ正、遠クリップは近クリップより大きい有限、縦視野角は0より大きく円周率より小さい
/// (その半角の正接も有限かつ正であることを重ねて確かめる)、横縦比は有限かつ正である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 射影の復元 {
    近クリップ: メートル,
    遠クリップ: メートル,
    縦視野角の半角の正接: f32,
    横縦比: f32,
    画素内ずらし: 画素内ずらし,
}

impl 射影の復元 {
    pub fn 生成する(
        近クリップ: メートル,
        遠クリップ: メートル,
        縦視野角: ラジアン,
        横縦比: f32,
        画素内ずらし: 画素内ずらし,
    ) -> Result<Self, 局所可視性エラー> {
        if !近クリップ.値().is_finite() || 近クリップ.値() <= 0.0 {
            return Err(局所可視性エラー::値域外("近クリップ", 近クリップ.値()));
        }
        if !遠クリップ.値().is_finite() || 遠クリップ.値() <= 近クリップ.値() {
            return Err(局所可視性エラー::上下の順序が逆(
                "クリップ面",
                近クリップ.値(),
                遠クリップ.値(),
            ));
        }
        if !縦視野角.値().is_finite() || 縦視野角.値() <= 0.0 || 縦視野角.値() >= std::f32::consts::PI {
            return Err(局所可視性エラー::値域外("縦視野角", 縦視野角.値()));
        }
        let 半角の正接 = (縦視野角.値() * 0.5).tan();
        if !半角の正接.is_finite() || 半角の正接 <= 0.0 {
            return Err(局所可視性エラー::値域外("縦視野角の半角の正接", 半角の正接));
        }
        if !横縦比.is_finite() || 横縦比 <= 0.0 {
            return Err(局所可視性エラー::値域外("横縦比", 横縦比));
        }
        Ok(Self {
            近クリップ,
            遠クリップ,
            縦視野角の半角の正接: 半角の正接,
            横縦比,
            画素内ずらし,
        })
    }

    pub fn 画素内ずらし(self) -> 画素内ずらし {
        self.画素内ずらし
    }

    pub fn 近クリップ(self) -> メートル {
        self.近クリップ
    }

    pub fn 遠クリップ(self) -> メートル {
        self.遠クリップ
    }

    pub fn 縦視野角の半角の正接(self) -> f32 {
        self.縦視野角の半角の正接
    }

    pub fn 横縦比(self) -> f32 {
        self.横縦比
    }

    /// 深度が表すカメラからの奥行き。近クリップ面で近クリップ距離、遠クリップ面で遠クリップ距離になる。
    pub fn 奥行きを復元する(self, 深度: f32) -> メートル {
        let 近 = self.近クリップ.値();
        let 遠 = self.遠クリップ.値();
        メートル::生成する(遠 * 近 / (遠 - 深度 * (遠 - 近)))
    }

    /// 奥行きが取る深度。合成深度の焼き上げがこの向きを使う。
    pub fn 深度へ写す(self, 奥行き: メートル) -> f32 {
        let 近 = self.近クリップ.値();
        let 遠 = self.遠クリップ.値();
        遠 * (近 - 奥行き.値()) / (奥行き.値() * (近 - 遠))
    }
}
