//! 深度だけからビュー空間の法線を組み立てる工程。受け取るのは深度画像と射影と不連続の閾値と画素の位置、
//! 返すのは再構成した法線、または面が定まらないという答えである。
//!
//! 法線の添付を持たずに深度から起こすのは、添付を足すと深度プリパスが小さなG-bufferになり、帯域と
//! 材質・スキニングの一致条件が増えるためである(`参照: _doc/設計/放射輝度問い合わせ階層.md`「IIa(SSAO)の設計」)。
//!
//! 面が定まらない画素は遮蔽なしへ退避する。輪郭では両隣が別の面に載り、どちらを選んでも実在しない面の
//! 法線が出るためである。退避で失うのは輪郭1列の陰りだけであり、誤った法線が作る黒い縁取りより害が小さい。

use blitz_math::{ビュー, 位置};

use super::depth_image::深度画像;
use super::neighbor_selection::{差分の軸, 軸の隣点を選ぶ, 隣点の選択};
use super::projection::射影の復元;
use super::same_surface_tolerance::同一面の許容倍率;
use super::view_direction::{ビュー空間の向き, 外積の向き};
use super::view_displacement::ビュー空間の変位;
use super::view_position::画素中心の位置を復元する;

/// 法線の再構成の結果。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 法線の再構成結果 {
    再構成できた(ビュー空間の向き),
    /// 軸のどちらかで同じ面に載る隣点が無いか、選んだ2つの変位が平行で面が張れない。
    面が定まらない,
}

/// 画素の法線。返す法線は必ずカメラの側を向く。
/// 前提: 呼び出し元はその画素にジオメトリが描かれていることを確かめている。
pub fn ビュー空間法線を再構成する(
    深度画像: &深度画像,
    射影: 射影の復元,
    許容: 同一面の許容倍率,
    横: u32,
    縦: u32,
) -> 法線の再構成結果 {
    let 標点 = 画素中心の位置を復元する(射影, 深度画像.寸法(), 横, 縦, 深度画像.深度(横, 縦));
    let 隣点の選択::選べた(横変位) = 軸の隣点を選ぶ(深度画像, 射影, 標点, 許容, 差分の軸::横, 横, 縦) else {
        return 法線の再構成結果::面が定まらない;
    };
    let 隣点の選択::選べた(縦変位) = 軸の隣点を選ぶ(深度画像, 射影, 標点, 許容, 差分の軸::縦, 横, 縦) else {
        return 法線の再構成結果::面が定まらない;
    };
    let Some(向き) = 外積の向き(横変位, 縦変位) else {
        return 法線の再構成結果::面が定まらない;
    };
    法線の再構成結果::再構成できた(カメラの側へ向ける(向き, 標点))
}

/// 外積の向きは隣点を選んだ側で符号が入れ替わるため、カメラから標点へ向かう向きと逆を向く側へ揃える。
fn カメラの側へ向ける(向き: ビュー空間の向き, 標点: 位置<ビュー>) -> ビュー空間の向き {
    let 視線 = ビュー空間の変位::生成する(標点.x(), 標点.y(), 標点.z()).向きへ正規化する();
    match 視線 {
        Some(視線) if 向き.内積(視線) > 0.0 => 向き.反転する(),
        _ => 向き,
    }
}
