//! 倍精度で組み立てた量を単精度へ狭める境界。受け取るのは倍精度の値または符号なし整数、返すのは単精度である。
//!
//! 標準ライブラリは符号なし整数から単精度への型付き変換を持たず、数値の`as`キャストは規約で禁じているため、
//! glamのベクタ縮小を1成分に使う(`crates/blitz_render/src/atmosphere/narrowing.rs`が同じ手を採る)。
//!
//! 整数からの経路が必ず倍精度を通るのは、画素の通し番号も標本の添字も倍精度なら誤差なく表せるためである。
//! 単精度へ落ちるのはこの1箇所だけであり、丸めの入る場所が読み手にとって1つに定まる。

use glam::DVec3;

pub(super) fn 単精度へ狭める(値: f64) -> f32 {
    DVec3::splat(値).as_vec3().x
}

pub(super) fn 整数を単精度へ狭める(値: u32) -> f32 {
    単精度へ狭める(f64::from(値))
}
