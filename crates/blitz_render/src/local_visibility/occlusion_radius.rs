//! 遮蔽を探しに行く半球の半径という量そのもの。触れる状態を持たず、担うのは値域の保証だけである。
//!
//! 単位をビュー空間のメートルにするのは、遮蔽が世界の大きさで決まる現象だからである。画面の画素数で
//! 半径を持つと、同じ物体がカメラの距離で違う濃さの遮蔽を持ち、近づくだけで絵が変わる。

use blitz_math::メートル;

use super::error::局所可視性エラー;

/// 遮蔽の標本を置く半球の半径。
/// 不変条件: 有限かつ正である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 遮蔽半径 {
    長さ: メートル,
}

impl 遮蔽半径 {
    pub fn 生成する(長さ: メートル) -> Result<Self, 局所可視性エラー> {
        if !長さ.値().is_finite() || 長さ.値() <= 0.0 {
            return Err(局所可視性エラー::値域外("遮蔽半径", 長さ.値()));
        }
        Ok(Self { 長さ })
    }

    pub fn 長さ(self) -> メートル {
        self.長さ
    }
}
