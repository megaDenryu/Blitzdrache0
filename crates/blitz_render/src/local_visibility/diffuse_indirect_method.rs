//! 世界が宣言する拡散間接方式の、描画側での表し方。担うのはパスを積むかどうかの1つの判定だけである。
//!
//! 間接照明方針・露出方式と独立の軸にするのは、局所可視性補正が拡散間接照度へ掛かる係数であって、
//! 照度そのものの供給元でも画の完成の段でもないためである。定数近似の世界でも遠方環境の世界でも同じように掛かる。
//!
//! 方式で消費側の枝を分けないのは、定数近似と局所可視性補正の組み合わせを不正状態にしないためである。
//! 環境のみの世界では遮蔽なしの符号値だけを持つ画像が束縛され、掛け算が値を1ビットも変えない
//! (`参照: _doc/設計/放射輝度問い合わせ階層.md`「IIaの実装設計」)。

/// 世界が宣言する拡散間接照度の作り方。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 拡散間接方式 {
    環境のみ,               // 間接照明の供給元が答えた拡散間接照度をそのまま使う。
    局所可視性補正付き環境, // 同じ拡散間接照度へ、深度から求めた局所可視度を掛ける。
}

impl 拡散間接方式 {
    /// 遮蔽の標本化とぼかしのパスをそのフレームへ積むか。環境のみの世界では1本も積まない。
    pub(crate) fn パスを積むか(self) -> bool {
        matches!(self, Self::局所可視性補正付き環境)
    }
}
