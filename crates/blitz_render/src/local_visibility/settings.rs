//! 局所可視度の焼き上げが要る設定の全体。触れる状態を持たず、担うのは2工程ぶんの設定を1組で運ぶことだけである。
//!
//! 遮蔽とぼかしを1つに束ねるのは、2つが必ず対で選ばれるためである。ぼかしの窓の広さは遮蔽の標本を回す
//! 回転の本数を均せる広さでなければならず、片方だけを差し替えると帯状の模様が残る。

use super::blur_settings::両側ぼかしの設定;
use super::occlusion_settings::遮蔽の設定;

/// 局所可視性補正の設定の全体。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 局所可視性の設定 {
    遮蔽: 遮蔽の設定,
    ぼかし: 両側ぼかしの設定,
}

impl 局所可視性の設定 {
    pub fn 生成する(遮蔽: 遮蔽の設定, ぼかし: 両側ぼかしの設定) -> Self {
        Self { 遮蔽, ぼかし }
    }

    /// 仮置きの初期値。内訳の根拠はそれぞれの設定の側にある。
    pub fn 既定() -> Self {
        Self::生成する(遮蔽の設定::既定(), 両側ぼかしの設定::既定())
    }

    pub fn 遮蔽(self) -> 遮蔽の設定 {
        self.遮蔽
    }

    pub fn ぼかし(self) -> 両側ぼかしの設定 {
        self.ぼかし
    }
}
