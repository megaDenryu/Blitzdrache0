//! ビュー空間の単位向きという量そのもの。触れる状態を持たず、担うのは長さが1であることの保証と、
//! 向きどうしの内積、そして2つの変位から向きを作ることである。
//!
//! 変位と別の型にするのは、向きが無次元であり長さが1であるのに対し、変位が長さの次元を持ち大きさが
//! 自由だからである。同じ型にすると、正規化していないベクトルを法線として渡す誤りが型では止まらない。
//!
//! 2つの変位の外積は面積の次元を持つため値として保持せず、正規化した向きだけを返す。

use super::error::局所可視性エラー;
use super::view_displacement::ビュー空間の変位;

/// 長さが1に保たれた検証の許容。単精度の平方根と除算を通した正規化がこの幅に収まる。
const 単位の長さの許容: f32 = 1.0e-3;

/// ビュー空間の単位向き。成分の並びは横・縦・奥であり、奥は視線の逆向きが正である。
/// 不変条件: 全成分が有限で、長さが1から単位の長さの許容の内側にある。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ビュー空間の向き {
    成分: [f32; 3],
}

impl ビュー空間の向き {
    pub fn 生成する(成分: [f32; 3]) -> Result<Self, 局所可視性エラー> {
        let 長さの二乗 = 成分.iter().map(|値| 値 * 値).sum::<f32>();
        if !長さの二乗.is_finite() {
            return Err(局所可視性エラー::値域外("ビュー空間の向きの長さの二乗", 長さの二乗));
        }
        let 長さ = 長さの二乗.sqrt();
        if (長さ - 1.0).abs() > 単位の長さの許容 {
            return Err(局所可視性エラー::値域外("ビュー空間の向きの長さ", 長さ));
        }
        Ok(Self { 成分 })
    }

    pub fn 成分(self) -> [f32; 3] {
        self.成分
    }

    pub fn 内積(self, 相手: Self) -> f32 {
        self.成分[0] * 相手.成分[0] + self.成分[1] * 相手.成分[1] + self.成分[2] * 相手.成分[2]
    }

    pub fn 反転する(self) -> Self {
        Self {
            成分: [-self.成分[0], -self.成分[1], -self.成分[2]],
        }
    }
}

/// 2つの変位が張る面に垂直な向き。2つが平行で外積が潰れる場合は向きが定まらないため値なしを返す。
pub fn 外積の向き(第一: ビュー空間の変位, 第二: ビュー空間の変位) -> Option<ビュー空間の向き> {
    let 甲 = 第一.成分();
    let 乙 = 第二.成分();
    let 外積 = [
        甲[1] * 乙[2] - 甲[2] * 乙[1],
        甲[2] * 乙[0] - 甲[0] * 乙[2],
        甲[0] * 乙[1] - 甲[1] * 乙[0],
    ];
    let 長さ = 外積.iter().map(|値| 値 * 値).sum::<f32>().sqrt();
    if !長さ.is_finite() || 長さ <= 0.0 {
        return None;
    }
    ビュー空間の向き::生成する([外積[0] / 長さ, 外積[1] / 長さ, 外積[2] / 長さ]).ok()
}
