//! 中央差分に使う隣の画素を軸ごとに1つ選ぶ工程。受け取るのは深度画像と射影と標点と同一面の許容と軸と画素の位置、
//! 返すのは選んだ隣点への変位、または同じ面に載る隣点が無いという答えである。
//!
//! 両隣のうち復元した位置までの距離が小さい側を選ぶのは、物の輪郭では片側の隣点が背景の遠い面に載るためである。
//! 常に片側だけを見ると、輪郭の内側1列の法線が背景へ向かって倒れ、縁が黒く縁取られる。
//!
//! 深度の値の差でなく復元した位置の距離で比べるのは、深度が奥行きに対して線形でないためである。
//! 同じ値の差が近くでは数ミリ、遠くでは数メートルを表す。

use blitz_math::{ビュー, 位置};

use super::depth_image::深度画像;
use super::image_size::画像の寸法;
use super::projection::射影の復元;
use super::same_surface_tolerance::同一面の許容倍率;
use super::view_displacement::ビュー空間の変位;
use super::view_position::{カメラからの奥行き, 画素が覆う幅を求める, 画素中心の位置を復元する};

/// 中央差分を採る軸。縦は画面の下向きが正である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 差分の軸 {
    横,
    縦,
}

/// 軸の両側の隣接画素。画面の外に落ちた側は値なしである。
struct 軸の両隣 {
    負側: Option<(u32, u32)>,
    正側: Option<(u32, u32)>,
}

/// 軸1つぶんの隣点の選択の結果。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 隣点の選択 {
    選べた(ビュー空間の変位), // 選んだ隣点への変位。向きは常に画素の位置が増える側である
    同じ面の隣点が無い,       // 両隣が画面の外か空か、選んだ隣点が許容より遠く同じ面に載っていない
}

/// その軸で採る隣点への変位。
pub fn 軸の隣点を選ぶ(
    深度画像: &深度画像,
    射影: 射影の復元,
    標点: 位置<ビュー>,
    許容: 同一面の許容倍率,
    軸: 差分の軸,
    横: u32,
    縦: u32,
) -> 隣点の選択 {
    let 両隣 = 画面に収まる隣接画素(深度画像.寸法(), 軸, 横, 縦);
    let 選んだ = match (
        候補の変位(深度画像, 射影, 標点, 両隣.負側, false),
        候補の変位(深度画像, 射影, 標点, 両隣.正側, true),
    ) {
        (Some(負), Some(正)) if 正.長さ().値() < 負.長さ().値() => 正,
        (Some(負), Some(_)) => 負,
        (Some(片方), None) | (None, Some(片方)) => 片方,
        (None, None) => return 隣点の選択::同じ面の隣点が無い,
    };
    let 覆う幅 = 画素が覆う幅を求める(射影, 深度画像.寸法(), カメラからの奥行き(標点));
    if 選んだ.長さ().値() > 許容.距離の上限(覆う幅).値() {
        return 隣点の選択::同じ面の隣点が無い;
    }
    隣点の選択::選べた(選んだ)
}

/// 軸の両側の隣接画素のうち、画面に収まるもの。
fn 画面に収まる隣接画素(寸法: 画像の寸法, 軸: 差分の軸, 横: u32, 縦: u32) -> 軸の両隣 {
    let (負, 正) = match 軸 {
        差分の軸::横 => (横.checked_sub(1).map(|隣| (隣, 縦)), 横.checked_add(1).map(|隣| (隣, 縦))),
        差分の軸::縦 => (縦.checked_sub(1).map(|隣| (横, 隣)), 縦.checked_add(1).map(|隣| (横, 隣))),
    };
    let 収まるか = |位置: &(u32, u32)| 寸法.含むか(位置.0, 位置.1);
    軸の両隣 {
        負側: 負.filter(収まるか),
        正側: 正.filter(収まるか),
    }
}

/// 隣点への変位。向きは画素の位置が増える側へ揃えるため、負側の隣点では標点から見た向きを反転して作る。
fn 候補の変位(
    深度画像: &深度画像,
    射影: 射影の復元,
    標点: 位置<ビュー>,
    隣点: Option<(u32, u32)>,
    正側か: bool,
) -> Option<ビュー空間の変位> {
    let (横, 縦) = 隣点?;
    if !深度画像.ジオメトリがあるか(横, 縦) {
        return None;
    }
    let 隣 = 画素中心の位置を復元する(射影, 深度画像.寸法(), 横, 縦, 深度画像.深度(横, 縦));
    Some(if 正側か {
        ビュー空間の変位::位置の差から(隣, 標点)
    } else {
        ビュー空間の変位::位置の差から(標点, 隣)
    })
}
