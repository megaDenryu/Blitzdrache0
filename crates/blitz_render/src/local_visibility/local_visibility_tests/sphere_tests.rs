//! 球の上で可視度が連続に変わり、周りの空が遮蔽なしになることを確かめる。担うのは、空の画素が1であること、
//! 隣り合う画素の差が小さいこと、そしてその差の検査が段差では成り立たないことの対である。
//!
//! 球を選ぶのは、法線が画面のどの向きへも滑らかに向きを変える形だからである。標本の向きの組み立てか
//! 接基底の作り方に飛びがあると、法線が特定の向きを取る画素の帯だけ値が跳ぶ。
//!
//! 凸の面は自分を遮蔽しないため、実測では球の全画素が遮蔽なしになり隣り合う差は0である。この0は
//! 「可視度を常に1にする実装」でも出るため、同じ集計が段差では0.2625になることを対で確かめる。

use super::visibility_statistics::地の在る隣接画素の最大の差;
use super::{場面を焼く, 検査する幅, 検査する高さ, 段差, 球};

/// 隣り合う画素の差の上限。既定の設定での実測は球が0.0000、段差が0.2625であり、この2つを分ける値として
/// 標本数16の1本ぶん(0.0625)より大きく段差の実測の半分より小さい0.1を採った。
const 連続とみなす差の上限: f32 = 0.1;

#[test]
fn 球の周りの空は遮蔽なしになる() {
    let (深度, 可視度) = 場面を焼く(球());
    for 縦 in 0..検査する高さ {
        for 横 in 0..検査する幅 {
            if !深度.ジオメトリがあるか(横, 縦) {
                let 値 = 可視度.可視度(横, 縦).値();
                assert!((値 - 1.0).abs() < 1.0e-6, "空の画素(横{横} 縦{縦})に遮蔽が出た(可視度{値})");
            }
        }
    }
}

#[test]
fn 球の上では隣り合う画素の可視度が連続に変わる() {
    let (深度, 可視度) = 場面を焼く(球());
    let 最大の差 = 地の在る隣接画素の最大の差(&深度, &可視度);
    assert!(最大の差 < 連続とみなす差の上限, "球の上で可視度が跳んだ(最大の差{最大の差})");
}

/// 同じ差の検査が段差では落ちることを確かめる。この対が無いと、可視度を常に1にする実装でも連続の検査は通る。
#[test]
fn 隣り合う画素の差の検査は段差では成り立たない() {
    let (深度, 可視度) = 場面を焼く(段差());
    let 最大の差 = 地の在る隣接画素の最大の差(&深度, &可視度);
    assert!(最大の差 >= 連続とみなす差の上限, "段差の境界でも可視度が跳ばなかった(最大の差{最大の差})");
}
