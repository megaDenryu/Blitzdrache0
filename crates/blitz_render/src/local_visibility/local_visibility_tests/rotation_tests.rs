//! 標本の回転が画素の位置だけで決まることと、有限個の回転が互いに別の向きを指すことを確かめる。
//! 担うのは、決定性、近くの画素が同じ回転へ偏らないこと、角が重ならないこと、回転が長さを変えないことである。
//!
//! 決定性は静止した画面でフレームごとに絵が動かないことの根拠である。偏らないことは、少ない標本数の偏りが
//! 帯として焼き付かないための条件であり、これが崩れると両側ぼかしで均しても模様が残る。

use std::collections::BTreeSet;

use crate::local_visibility::{全回転, 標本の回転の本数, 画素位置から回転を選ぶ};

/// 近くの画素で現れてほしい回転の種類の下限。4画素四方の16画素が16通りの回転をすべて引く保証は無いため、
/// 半分を下限に採る。1種類しか出ない実装(位置を読んでいない・剰余の取り違え)はこの下限で落ちる。
const 四画素四方で現れる種類の下限: usize = 8;

#[test]
fn 同じ画素位置は必ず同じ回転を選ぶ() {
    for 縦 in 0..8 {
        for 横 in 0..8 {
            assert_eq!(画素位置から回転を選ぶ(横, 縦), 画素位置から回転を選ぶ(横, 縦));
        }
    }
}

#[test]
fn 近くの画素は違う回転へ散らばる() {
    let mut 種類 = BTreeSet::new();
    for 縦 in 0..4_u32 {
        for 横 in 0..4_u32 {
            let 回転 = 画素位置から回転を選ぶ(横, 縦);
            種類.insert((回転.余弦().to_bits(), 回転.正弦().to_bits()));
        }
    }
    assert!(
        種類.len() >= 四画素四方で現れる種類の下限,
        "4画素四方で現れた回転が{}種類しかない",
        種類.len()
    );
}

#[test]
fn 回転の本数ぶんの角はすべて別の向きを指す() {
    let 種類: BTreeSet<(u32, u32)> = 全回転().map(|回転| (回転.余弦().to_bits(), 回転.正弦().to_bits())).collect();
    let 本数 = usize::try_from(標本の回転の本数).unwrap();
    assert_eq!(種類.len(), 本数, "回転の角が重なっている");
}

#[test]
fn 回転は平面の向きの長さを変えない() {
    for 回転 in 全回転() {
        let 回した = 回転.平面の向きを回す([0.6, 0.8]);
        let 長さ = (回した[0] * 回した[0] + 回した[1] * 回した[1]).sqrt();
        assert!((長さ - 1.0).abs() < 1.0e-5, "回転が長さを変えた({長さ})");
    }
}
