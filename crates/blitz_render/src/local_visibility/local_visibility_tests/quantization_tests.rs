//! 局所可視度と8ビットの符号値の往復を確かめる。担うのは、両端が両端へ写ること、丸めが最も近い符号値を選ぶこと、
//! 符号値から戻した可視度が元の符号値へ戻ることである。
//!
//! この丸めは検収の突き合わせの土俵そのものである。ここが1段ずれると、正本と写しが同じ値を出していても
//! 検収が食い違いを報告する。

use crate::local_visibility::{局所可視度, 局所可視度の符号値};

#[test]
fn 両端は両端の符号値へ写る() {
    assert_eq!(局所可視度の符号値::量子化する(局所可視度::生成する(0.0).unwrap()).値(), 0);
    assert_eq!(局所可視度の符号値::量子化する(局所可視度::遮蔽なし()).値(), 255);
}

#[test]
fn 丸めは最も近い符号値を選ぶ() {
    let 一段 = 1.0 / 255.0;
    assert_eq!(局所可視度の符号値::量子化する(局所可視度::生成する(一段 * 0.49).unwrap()).値(), 0);
    assert_eq!(局所可視度の符号値::量子化する(局所可視度::生成する(一段 * 0.51).unwrap()).値(), 1);
    assert_eq!(局所可視度の符号値::量子化する(局所可視度::生成する(一段 * 1.49).unwrap()).値(), 1);
}

#[test]
fn 符号値から戻した可視度は同じ符号値へ写る() {
    for 符号値 in 0..=255_u8 {
        let 可視度 = 局所可視度の符号値::量子化する(局所可視度::生成する(f32::from(符号値) / 255.0).unwrap());
        assert_eq!(可視度.値(), 符号値, "符号値{符号値}が往復で変わった");
    }
}

#[test]
fn 遮蔽の割合から求めた可視度は値域に収まる() {
    for 割合 in [-0.001_f32, 0.0, 0.5, 1.0, 1.001] {
        let 可視度 = 局所可視度::遮蔽の割合から求める(割合).値();
        assert!((0.0..=1.0).contains(&可視度), "割合{割合}から値域の外の可視度{可視度}が出た");
    }
}
