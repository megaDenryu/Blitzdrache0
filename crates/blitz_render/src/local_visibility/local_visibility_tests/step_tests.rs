//! 段差で暗くなるのが接触側だけであることを確かめる。担うのは、奥の面の境界寄りが低下すること、
//! 手前の面と境界から離れた奥の面が遮蔽なしのままであること、そしてその低下が遮蔽半径から出ていることである。
//!
//! 段差は手前の面と奥の面が接する形であり、奥の面の境界寄りが谷の内側(接触側)、手前の面の境界寄りが
//! 尾根の外側(凸側)にあたる。凸側が暗くなる実装は、標本の向きか奥行きの比べ方の符号を取り違えている。

use blitz_math::メートル;

use super::visibility_statistics::地の在る画素の最小可視度;
use super::{場面を焼く, 場面を設定で焼く, 局所可視性の設定, 検査する設定, 検査する高さ, 段差, 段差の境界};
use crate::local_visibility::{遮蔽の設定, 遮蔽半径};

/// 判定に使う縦位置。画面の縦の真ん中であり、上下の端の画素を避ける。
const 検査する縦: u32 = 検査する高さ / 2;
/// 境界からの隔たり。接触側は遮蔽半径の内側、離れた側は外側に取る。既定の設定での接触側の実測は0.815である。
const 接触側の隔たり: u32 = 2;
const 離れた側の隔たり: u32 = 30;
/// 接触側が暗くなったと認める可視度の上限。実測0.815と遮蔽なしの1の間に採る。
const 接触側とみなす可視度の上限: f32 = 0.9;

#[test]
fn 段差の接触側は暗くなり離れた側は遮蔽なしのままである() {
    let (_, 可視度) = 場面を焼く(段差());
    let 接触側 = 可視度.可視度(段差の境界 + 接触側の隔たり, 検査する縦).値();
    let 離れた側 = 可視度.可視度(段差の境界 + 離れた側の隔たり, 検査する縦).値();
    assert!(接触側 < 接触側とみなす可視度の上限, "段差の接触側が暗くなっていない(可視度{接触側})");
    assert!((離れた側 - 1.0).abs() < 1.0e-6, "境界から離れた奥の面に遮蔽が出た(可視度{離れた側})");
}

#[test]
fn 段差の凸側は全画素で遮蔽なしになる() {
    let (深度, 可視度) = 場面を焼く(段差());
    let mut 最小 = 1.0_f32;
    for 縦 in 0..検査する高さ {
        for 横 in 0..段差の境界 {
            if 深度.ジオメトリがあるか(横, 縦) {
                最小 = 最小.min(可視度.可視度(横, 縦).値());
            }
        }
    }
    assert!((最小 - 1.0).abs() < 1.0e-6, "段差の凸側に遮蔽が出た(最小可視度{最小})");
}

/// 接触側の低下が遮蔽半径の内側に遮蔽物が居ることから出ていることを、半径を段差より十分小さくして確かめる。
/// この対が無いと、接触側が暗いという観察が半径と無関係な定数から出ていても気づけない。
#[test]
fn 接触側の低下は遮蔽半径から出ている() {
    let 既定 = 検査する設定();
    let 小さい半径 = 遮蔽半径::生成する(メートル::生成する(0.01)).unwrap();
    let 遮蔽 = 遮蔽の設定::生成する(
        小さい半径,
        既定.遮蔽().深度バイアス(),
        既定.遮蔽().距離減衰(),
        既定.遮蔽().標本数(),
        既定.遮蔽().同一面の許容(),
    );
    let (深度, 可視度) = 場面を設定で焼く(段差(), 局所可視性の設定::生成する(遮蔽, 既定.ぼかし()));
    let 最小 = 地の在る画素の最小可視度(&深度, &可視度);
    assert!(
        (最小 - 1.0).abs() < 1.0e-6,
        "遮蔽半径を段差より十分小さくしても遮蔽が残った(最小可視度{最小})"
    );
}
