//! 法線が連続に変わる凹んだ面で、遮蔽が生まれつつ可視度に不連続が出ないことを確かめる。担うのは、
//! 可視度が定数でないこと、面の上に飛びが無いこと、そして遮蔽の強さが底で最も濃くなることである。
//!
//! この場面が要るのは、平面が全画素1.0000、球が凸のため全画素1.0000になり、どちらも「法線が向きを変える
//! 領域で標本の回転と接基底が連続な値を作るか」を1つも見ていないためである。凹面はその両方を同時に見る
//! 唯一の場面であり、IIa-3で正本と写しを突き合わせるときの比較条件にもなる。
//!
//! 細かい寸法で焼くのは、遮蔽の深度バイアスが1画素の覆う幅に比例するためである。粗い画面では下限が
//! 曲面の陰りより大きくなり、遮蔽が1画素も出ない。

use super::test_scenes::{凹面, 正対する平面};
use super::visibility_statistics::{地の在る画素の最小可視度, 地の在る隣接画素の最大の差};
use super::{場面を寸法と設定で焼く, 検査する設定, 細かい寸法};

/// 面の上で認める隣り合う画素の差の上限。実測は0.0200であり、標本数16の1本ぶん(0.0625)より小さい。
/// 両側ぼかしが画素ごとの回転の違いを均していることがこの値の意味である。段差の境界で出る0.2625とは
/// ひと桁離れており、球の検査と同じ0.1を分ける値に採る。
const 面の上で認める差の上限: f32 = 0.1;
/// 遮蔽が出たと認める最小可視度の上限。実測は凹面が0.8600、同じ寸法の平面が1.0000である。
const 遮蔽が出たと認める上限: f32 = 0.95;

#[test]
fn 凹面には遮蔽が生まれる() {
    let (深度, 可視度) = 場面を寸法と設定で焼く(凹面(), 細かい寸法(), 検査する設定());
    let 最小 = 地の在る画素の最小可視度(&深度, &可視度);
    assert!(最小 < 遮蔽が出たと認める上限, "凹面に遮蔽が生まれなかった(最小可視度{最小})");
}

#[test]
fn 凹面の可視度には不連続が出ない() {
    let (深度, 可視度) = 場面を寸法と設定で焼く(凹面(), 細かい寸法(), 検査する設定());
    let 最大の差 = 地の在る隣接画素の最大の差(&深度, &可視度);
    assert!(最大の差 < 面の上で認める差の上限, "凹面の上で可視度が跳んだ(最大の差{最大の差})");
}

/// 上の2つが同じ場面で同時に成り立つことこそが見たい性質である。平面を同じ寸法で焼くと遮蔽の側だけが
/// 落ちることを確かめ、「遮蔽が生まれる」の検査が定数を返す実装でも通るものでないことを示す。
#[test]
fn 遮蔽が生まれるという検査は平面では成り立たない() {
    let (深度, 可視度) = 場面を寸法と設定で焼く(正対する平面(), 細かい寸法(), 検査する設定());
    let 最小 = 地の在る画素の最小可視度(&深度, &可視度);
    assert!(最小 >= 遮蔽が出たと認める上限, "平面でも遮蔽が生まれた(最小可視度{最小})");
}
