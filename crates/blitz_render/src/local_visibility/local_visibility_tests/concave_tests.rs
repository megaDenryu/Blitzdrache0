//! 法線が連続に変わる凹んだ面で、可視度が場所によって変わりつつ不連続を持たないことを確かめる。担うのは、
//! 可視度の幅が有意に正であること、底から縁へ向かって薄くなること、面の上に飛びが無いことである。
//!
//! この場面が要るのは、平面が全画素1.0000、球が凸のため全画素1.0000になり、どちらも「法線が向きを変える
//! 領域で標本の回転と接基底が連続な値を作るか」を1つも見ていないためである。凹面はその両方を同時に見る
//! 唯一の場面であり、IIa-3で正本と写しを突き合わせるときの比較条件にもなる。
//!
//! 最小値と隣接差だけを見る検査は、面全体を同じ値で返す実装でも通ってしまう。可視度の幅と、底と肩と縁の
//! 大小の並びを別に固定することで、値が場所によって変わっていることそのものを検査の対象にする。
//!
//! 細かい寸法で焼くのは、遮蔽の深度バイアスが1画素の覆う幅に比例するためである。粗い画面では下限が
//! 曲面の陰りより大きくなり、遮蔽が1画素も出ない。

use super::test_scenes::{凹面, 正対する平面};
use super::visibility_statistics::{
    地の在る画素の可視度の幅, 地の在る画素の最小可視度, 地の在る隣接画素の最大の差
};
use super::{場面を寸法と設定で焼く, 検査する設定, 細かい寸法};

/// 面の上で認める隣り合う画素の差の上限。横と縦の両方を数えた実測は0.0200であり、標本数16の1本ぶん
/// (0.0625)より小さい。両側ぼかしが画素ごとの回転の違いを均していることがこの値の意味である。
/// 段差の境界で出る0.2625とはひと桁離れており、球の検査と同じ0.1を分ける値に採る。
const 面の上で認める差の上限: f32 = 0.1;
/// 遮蔽が出たと認める最小可視度の上限。実測は凹面が0.8600、同じ寸法の平面が1.0000である。
const 遮蔽が出たと認める上限: f32 = 0.95;
/// 可視度が場所によって変わったと認める幅の下限。実測は0.1400であり、8ビットの1符号値(0.0039)の
/// 35倍を超える。面全体を同じ値で返す実装はこの検査で落ちる。
const 場所で変わったと認める幅の下限: f32 = 0.05;
/// 底と肩の間で認める隔たりの下限。実測は底0.8625・肩0.9825で0.1200である。
const 底と肩の隔たりの下限: f32 = 0.05;
/// 肩と縁の間で認める隔たりの下限。実測は肩0.9825・縁1.0000で0.0175である。
const 肩と縁の隔たりの下限: f32 = 0.005;

#[test]
fn 凹面には遮蔽が生まれる() {
    let (深度, 可視度) = 場面を寸法と設定で焼く(凹面(), 細かい寸法(), 検査する設定());
    let 最小 = 地の在る画素の最小可視度(&深度, &可視度);
    assert!(最小 < 遮蔽が出たと認める上限, "凹面に遮蔽が生まれなかった(最小可視度{最小})");
}

#[test]
fn 凹面の可視度は場所によって変わる() {
    let (深度, 可視度) = 場面を寸法と設定で焼く(凹面(), 細かい寸法(), 検査する設定());
    let 幅 = 地の在る画素の可視度の幅(&深度, &可視度);
    assert!(幅 > 場所で変わったと認める幅の下限, "凹面の可視度が場所によって変わらない(幅{幅})");
}

/// 底が最も濃く、軸から離れるほど薄くなることを固定する。凹面の遮蔽は軸までの距離で決まるため、
/// この並びが崩れる実装は標本の向きか奥行きの比べ方を取り違えている。
#[test]
fn 凹面は底から縁へ向かって薄くなる() {
    let (深度, 可視度) = 場面を寸法と設定で焼く(凹面(), 細かい寸法(), 検査する設定());
    let 画面の幅 = 深度.寸法().幅();
    let 中央の縦 = 深度.寸法().高さ() / 2;
    let 底 = 可視度.可視度(画面の幅 / 2, 中央の縦).値();
    let 肩 = 可視度.可視度(画面の幅 / 2 + 画面の幅 / 8, 中央の縦).値();
    let 縁 = 可視度.可視度(画面の幅 - 3, 中央の縦).値();
    assert!(底 + 底と肩の隔たりの下限 < 肩, "底{底}が肩{肩}より十分に濃くない");
    assert!(肩 + 肩と縁の隔たりの下限 < 縁, "肩{肩}が縁{縁}より十分に濃くない");
}

#[test]
fn 凹面の可視度には不連続が出ない() {
    let (深度, 可視度) = 場面を寸法と設定で焼く(凹面(), 細かい寸法(), 検査する設定());
    let 最大の差 = 地の在る隣接画素の最大の差(&深度, &可視度);
    assert!(最大の差 < 面の上で認める差の上限, "凹面の上で可視度が跳んだ(最大の差{最大の差})");
}

/// 遮蔽と可視度の幅の2つが平面では出ないことを確かめる。この対が無いと、どちらの検査も定数を返す実装で
/// 通るかどうかを読み手が決められない。
#[test]
fn 遮蔽と可視度の幅は平面では出ない() {
    let (深度, 可視度) = 場面を寸法と設定で焼く(正対する平面(), 細かい寸法(), 検査する設定());
    let 最小 = 地の在る画素の最小可視度(&深度, &可視度);
    let 幅 = 地の在る画素の可視度の幅(&深度, &可視度);
    assert!(最小 >= 遮蔽が出たと認める上限, "平面でも遮蔽が生まれた(最小可視度{最小})");
    assert!(幅 <= 場所で変わったと認める幅の下限, "平面でも可視度が場所によって変わった(幅{幅})");
}
