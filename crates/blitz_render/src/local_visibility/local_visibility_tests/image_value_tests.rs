//! 画像と場面の値オブジェクトが壊れた入力を拒むことを確かめる。担うのは、寸法と要素数の食い違い、
//! 深度の値域、射影の順序、そして3つの形の寸法の不整合が型付きの失敗になることである。
//!
//! 受け付ける入力の側も対で置く。拒む側だけを見ると、常に失敗を返す実装でも通ってしまう。

use blitz_math::{メートル, ラジアン};

use crate::local_visibility::{合成深度の場面, 射影の復元, 局所可視度, 局所可視度画像, 深度画像, 画像の寸法};

use super::検査する寸法;

#[test]
fn 画像の寸法は2画素に満たない辺を拒む() {
    assert!(画像の寸法::生成する(1, 8).is_err());
    assert!(画像の寸法::生成する(8, 0).is_err());
    assert!(画像の寸法::生成する(2, 2).is_ok());
}

#[test]
fn 射影は順序の逆と開いていない視野角を拒む() {
    let 近 = メートル::生成する(0.1);
    let 遠 = メートル::生成する(100.0);
    let 視野角 = ラジアン::生成する(1.0);
    assert!(射影の復元::生成する(メートル::生成する(0.0), 遠, 視野角, 1.0).is_err());
    assert!(射影の復元::生成する(遠, 近, 視野角, 1.0).is_err());
    assert!(射影の復元::生成する(近, 遠, ラジアン::生成する(0.0), 1.0).is_err());
    assert!(射影の復元::生成する(近, 遠, ラジアン::生成する(std::f32::consts::PI), 1.0).is_err());
    assert!(射影の復元::生成する(近, 遠, ラジアン::生成する(-1.0), 1.0).is_err());
    assert!(射影の復元::生成する(近, 遠, 視野角, 0.0).is_err());
    assert!(射影の復元::生成する(近, 遠, 視野角, 1.0).is_ok());
}

#[test]
fn 深度画像は要素数と値域の違反を拒む() {
    let 寸法 = 画像の寸法::生成する(2, 2).unwrap();
    assert!(深度画像::生成する(寸法, vec![0.5; 3]).is_err());
    assert!(深度画像::生成する(寸法, vec![0.5, 0.5, 1.5, 0.5]).is_err());
    assert!(深度画像::生成する(寸法, vec![0.5, 0.5, f32::NAN, 0.5]).is_err());
    assert!(深度画像::生成する(寸法, vec![0.5; 4]).is_ok());
}

#[test]
fn 局所可視度画像は要素数の違反を拒む() {
    let 寸法 = 画像の寸法::生成する(2, 2).unwrap();
    let 遮蔽なし = 局所可視度::遮蔽なし();
    assert!(局所可視度画像::生成する(寸法, vec![遮蔽なし; 3]).is_err());
    assert!(局所可視度画像::生成する(寸法, vec![遮蔽なし; 4]).is_ok());
}

#[test]
fn 合成深度の場面は不整合な寸法を拒む() {
    let 三メートル = メートル::生成する(3.0);
    assert!(合成深度の場面::平面(メートル::生成する(0.0), 0.0).is_err());
    assert!(合成深度の場面::平面(三メートル, 1.5).is_err());
    assert!(合成深度の場面::段差(メートル::生成する(4.0), 三メートル, 8).is_err());
    assert!(合成深度の場面::球(三メートル, メートル::生成する(4.0)).is_err());
    assert!(合成深度の場面::平面(三メートル, 0.5).is_ok());
    assert!(合成深度の場面::段差(三メートル, メートル::生成する(4.0), 8).is_ok());
    assert!(合成深度の場面::球(三メートル, メートル::生成する(1.0)).is_ok());
}

#[test]
fn 焼いた合成深度は寸法どおりの並びになる() {
    let 寸法 = 検査する寸法();
    let 場面 = 合成深度の場面::平面(メートル::生成する(3.0), 0.0).unwrap();
    let 深度 = crate::local_visibility::合成深度を焼く(場面, 寸法, super::検査する射影()).unwrap();
    assert_eq!(深度.寸法(), 寸法);
    assert!(深度.ジオメトリがあるか(0, 0));
}
