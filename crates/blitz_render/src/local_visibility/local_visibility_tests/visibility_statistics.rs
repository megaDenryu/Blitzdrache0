//! 焼いた可視度画像から判定に使う1つの数を取り出す集計。受け取るのは深度画像と可視度画像の対、
//! 返すのは最小の可視度または隣り合う画素の最大の差である。
//!
//! 集計をテストの本文から離すのは、複数のテストが同じ2つの数を別々の走査で数えると、走査の書き間違いが
//! テストごとに違う結果を出すためである。ジオメトリの無い画素を外す条件もここに1つだけ置く。

use crate::local_visibility::{局所可視度画像, 深度画像};

use super::{検査する幅, 検査する高さ};

/// ジオメトリが描かれている画素の中で最も小さい可視度。1つも無ければ1を返す。
pub(super) fn 地の在る画素の最小可視度(深度: &深度画像, 可視度: &局所可視度画像) -> f32 {
    let mut 最小 = 1.0_f32;
    for 縦 in 0..検査する高さ {
        for 横 in 0..検査する幅 {
            if 深度.ジオメトリがあるか(横, 縦) {
                最小 = 最小.min(可視度.可視度(横, 縦).値());
            }
        }
    }
    最小
}

/// 横に隣り合いどちらにもジオメトリがある画素の組で、可視度の差が最も大きい値。
pub(super) fn 地の在る隣接画素の最大の差(深度: &深度画像, 可視度: &局所可視度画像) -> f32 {
    let mut 最大 = 0.0_f32;
    for 縦 in 0..検査する高さ {
        for 横 in 1..検査する幅 {
            if 深度.ジオメトリがあるか(横, 縦) && 深度.ジオメトリがあるか(横 - 1, 縦) {
                let 差 = (可視度.可視度(横, 縦).値() - 可視度.可視度(横 - 1, 縦).値()).abs();
                最大 = 最大.max(差);
            }
        }
    }
    最大
}
