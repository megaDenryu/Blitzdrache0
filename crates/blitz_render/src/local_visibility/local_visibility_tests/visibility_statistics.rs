//! 焼いた可視度画像から判定に使う1つの数を取り出す集計。受け取るのは深度画像と可視度画像の対、
//! 返すのは最小の可視度・最大と最小の幅・隣り合う画素の最大の差のいずれかである。
//!
//! 集計をテストの本文から離すのは、複数のテストが同じ数を別々の走査で数えると、走査の書き間違いが
//! テストごとに違う結果を出すためである。ジオメトリの無い画素を外す条件もここに1つだけ置く。
//!
//! 隣り合う組は横と縦の両方を数える。法線が横にも縦にも向きを変える面では、接基底の組み方の飛びが
//! 縦の並びにだけ現れることがあり、横だけを数える集計はそれを1つも捉えられない。

use crate::local_visibility::{局所可視度画像, 深度画像};

/// ジオメトリが描かれている画素の中で最も小さい可視度。1つも無ければ1を返す。
pub(super) fn 地の在る画素の最小可視度(深度: &深度画像, 可視度: &局所可視度画像) -> f32 {
    地の在る画素の最小と最大(深度, 可視度).0
}

/// ジオメトリが描かれている画素の可視度の、最大と最小の幅。値が場所によって変わることをこの数が表す。
/// 1つも無ければ0を返す。
pub(super) fn 地の在る画素の可視度の幅(深度: &深度画像, 可視度: &局所可視度画像) -> f32 {
    let (最小, 最大) = 地の在る画素の最小と最大(深度, 可視度);
    (最大 - 最小).max(0.0)
}

fn 地の在る画素の最小と最大(深度: &深度画像, 可視度: &局所可視度画像) -> (f32, f32) {
    let mut 最小 = 1.0_f32;
    let mut 最大 = 0.0_f32;
    for 縦 in 0..深度.寸法().高さ() {
        for 横 in 0..深度.寸法().幅() {
            if 深度.ジオメトリがあるか(横, 縦) {
                let 値 = 可視度.可視度(横, 縦).値();
                最小 = 最小.min(値);
                最大 = 最大.max(値);
            }
        }
    }
    (最小, 最大)
}

/// 横または縦に隣り合いどちらにもジオメトリがある画素の組で、可視度の差が最も大きい値。
pub(super) fn 地の在る隣接画素の最大の差(深度: &深度画像, 可視度: &局所可視度画像) -> f32 {
    let mut 最大 = 0.0_f32;
    for 縦 in 0..深度.寸法().高さ() {
        for 横 in 0..深度.寸法().幅() {
            if !深度.ジオメトリがあるか(横, 縦) {
                continue;
            }
            let 値 = 可視度.可視度(横, 縦).値();
            if 横 > 0 && 深度.ジオメトリがあるか(横 - 1, 縦) {
                最大 = 最大.max((値 - 可視度.可視度(横 - 1, 縦).値()).abs());
            }
            if 縦 > 0 && 深度.ジオメトリがあるか(横, 縦 - 1) {
                最大 = 最大.max((値 - 可視度.可視度(横, 縦 - 1).値()).abs());
            }
        }
    }
    最大
}
