//! 量の値オブジェクトが壊れた設定を拒むことを確かめる。担うのは、各量の値域の外と、順序が逆の組が
//! 型付きの失敗になることである。
//!
//! 受け付ける値の側も対で置く。拒む側だけを見ると、常に失敗を返す実装でも通ってしまう。

use blitz_math::メートル;

use crate::local_visibility::{
    ビュー空間の向き, 両側ぼかしの設定, 同一面の許容倍率, 局所可視度, 遮蔽の標本数, 遮蔽の深度バイアス, 遮蔽の距離減衰, 遮蔽半径,
};

#[test]
fn 局所可視度は値域の外を拒む() {
    assert!(局所可視度::生成する(1.5).is_err());
    assert!(局所可視度::生成する(-0.1).is_err());
    assert!(局所可視度::生成する(f32::NAN).is_err());
    assert!(局所可視度::生成する(0.5).is_ok());
}

#[test]
fn 遮蔽半径は正でない長さを拒む() {
    assert!(遮蔽半径::生成する(メートル::生成する(0.0)).is_err());
    assert!(遮蔽半径::生成する(メートル::生成する(-1.0)).is_err());
    assert!(遮蔽半径::生成する(メートル::生成する(f32::INFINITY)).is_err());
    assert!(遮蔽半径::生成する(メートル::生成する(0.5)).is_ok());
}

#[test]
fn 標本数は零と上限超えを拒む() {
    assert!(遮蔽の標本数::生成する(0).is_err());
    assert!(遮蔽の標本数::生成する(4096).is_err());
    assert!(遮蔽の標本数::生成する(16).is_ok());
}

#[test]
fn 同一面の許容倍率は1以下を拒む() {
    assert!(同一面の許容倍率::生成する(1.0).is_err());
    assert!(同一面の許容倍率::生成する(0.5).is_err());
    assert!(同一面の許容倍率::生成する(4.0).is_ok());
}

#[test]
fn 距離減衰は順序が逆の倍率を拒む() {
    assert!(遮蔽の距離減衰::生成する(2.0, 1.0).is_err());
    assert!(遮蔽の距離減衰::生成する(1.0, 1.0).is_err());
    assert!(遮蔽の距離減衰::生成する(-0.5, 2.0).is_err());
    assert!(遮蔽の距離減衰::生成する(1.0, 2.0).is_ok());
}

#[test]
fn ぼかしの画素半径は零と上限超えを拒む() {
    let 許容 = 同一面の許容倍率::生成する(2.0).unwrap();
    assert!(両側ぼかしの設定::生成する(0, 許容).is_err());
    assert!(両側ぼかしの設定::生成する(64, 許容).is_err());
    assert!(両側ぼかしの設定::生成する(2, 許容).is_ok());
}

#[test]
fn ビュー空間の向きは単位でない成分を拒む() {
    assert!(ビュー空間の向き::生成する([0.0, 0.0, 2.0]).is_err());
    assert!(ビュー空間の向き::生成する([0.0, 0.0, 0.0]).is_err());
    assert!(ビュー空間の向き::生成する([f32::NAN, 0.0, 1.0]).is_err());
    assert!(ビュー空間の向き::生成する([0.0, 0.0, 1.0]).is_ok());
}

#[test]
fn 距離減衰の重みは差が広がるほど下がる() {
    let 減衰 = 遮蔽の距離減衰::生成する(1.0, 2.0).unwrap();
    let 半径 = 遮蔽半径::生成する(メートル::生成する(0.5)).unwrap();
    let 近い = 減衰.重みを求める(半径, メートル::生成する(0.4));
    let 中ほど = 減衰.重みを求める(半径, メートル::生成する(0.75));
    let 遠い = 減衰.重みを求める(半径, メートル::生成する(1.2));
    assert!((近い - 1.0).abs() < 1.0e-6, "半径の内側で重みが1でない({近い})");
    assert!(遠い.abs() < 1.0e-6, "断ち切りの外で重みが0でない({遠い})");
    assert!(中ほど < 近い && 中ほど > 遠い, "間の重みが単調でない({中ほど})");
}

#[test]
fn 深度バイアスは負の倍率を拒む() {
    assert!(遮蔽の深度バイアス::生成する(-1.0).is_err());
    assert!(遮蔽の深度バイアス::生成する(f32::NAN).is_err());
    assert!(遮蔽の深度バイアス::生成する(0.0).is_ok());
}
