//! 両側ぼかしが何をして何をしないかを確かめる。担うのは、画素ごとのばらつきを縮めること、面をまたいで
//! 暗さを持ち込まないこと、そして遮蔽の無い場面で陰りを作り出さないことである。
//!
//! ぼかしを通した画像だけを見ていると、ぼかしが何もしない実装でも他の性質の検査はすべて通る。
//! ここでは生の可視度とぼかした後を同じ場面で並べ、2つが違うことを対で確かめる。

use crate::local_visibility::{合成深度を焼く, 生の局所可視度を焼く};

use super::visibility_statistics::{地の在る画素の最小可視度, 地の在る隣接画素の最大の差};
use super::{
    場面を焼く, 検査する寸法, 検査する射影, 検査する設定, 検査する高さ, 正対する平面, 段差, 段差の境界
};

const 検査する縦: u32 = 検査する高さ / 2;

#[test]
fn 両側ぼかしは画素ごとのばらつきを縮める() {
    let 深度 = 合成深度を焼く(段差(), 検査する寸法(), 検査する射影()).unwrap();
    let 生 = 生の局所可視度を焼く(&深度, 検査する射影(), 検査する設定().遮蔽());
    let (_, 均した) = 場面を焼く(段差());
    let 生の差 = 地の在る隣接画素の最大の差(&深度, &生);
    let 均した差 = 地の在る隣接画素の最大の差(&深度, &均した);
    assert!(均した差 < 生の差, "ぼかしがばらつきを縮めていない(生{生の差} 均した{均した差})");
}

/// ぼかしは段差の向こう側の暗さを凸側へ持ち込まない。窓の広さは段差の境界から2画素に届く。
#[test]
fn 両側ぼかしは面をまたいで暗さを持ち込まない() {
    let (_, 均した) = 場面を焼く(段差());
    let 凸側 = 均した.可視度(段差の境界 - 1, 検査する縦).値();
    assert!((凸側 - 1.0).abs() < 1.0e-6, "段差の凸側の境界の列へ暗さが漏れた(可視度{凸側})");
}

/// 遮蔽の無い場面ではぼかしを通しても陰りが生まれないことを確かめる。均しが窓の外の値を混ぜていれば、
/// 画面の端で1を下回る。
#[test]
fn 遮蔽の無い場面ではぼかしが陰りを作らない() {
    let (深度, 均した) = 場面を焼く(正対する平面());
    let 最小 = 地の在る画素の最小可視度(&深度, &均した);
    assert!((最小 - 1.0).abs() < 1.0e-6, "遮蔽の無い場面でぼかしが陰りを作った(最小可視度{最小})");
}
