//! 画素内ずらしを与えた射影で、深度を書く側と位置を戻す側が同じ規約に立っていることを確かめる。
//!
//! 深度を書く側は`blitz_math`の`変換<クリップ, クリップ>::画素内ずらし`をビュー射影の後ろへ合成した行列であり、
//! 位置を戻す側は`射影の復元`が持つずらしである。この2つは別々のクレートに写しとして存在するため、
//! 符号や倍率が食い違っても片方だけを見るテストでは通ってしまう。ここが突き合わせる。

use blitz_math::{クリップ, ビュー, メートル, ラジアン, 位置, 変換, 画素内ずらし};

use crate::local_visibility::{位置が落ちる画素を求める, 射影の復元, 画像の寸法, 画素中心の位置を復元する};

use super::{検査する寸法, 検査する射影, 検査する幅, 検査する高さ};

const 近クリップ: f32 = 0.1;
const 遠クリップ: f32 = 2000.0;

fn 横縦比() -> f32 {
    f32::from(u16::try_from(検査する幅).unwrap()) / f32::from(u16::try_from(検査する高さ).unwrap())
}

fn 縦視野角() -> ラジアン {
    ラジアン::生成する(std::f32::consts::FRAC_PI_3)
}

fn 検査するずらし() -> 画素内ずらし {
    画素内ずらし::画素から生成する(0.25, -0.4, 検査する幅, 検査する高さ).unwrap()
}

fn ずらし付きの復元(ずらし: 画素内ずらし) -> 射影の復元 {
    射影の復元::生成する(
        メートル::生成する(近クリップ),
        メートル::生成する(遠クリップ),
        縦視野角(),
        横縦比(),
        ずらし,
    )
    .unwrap()
}

/// 深度を書く側の変換。透視投影の後ろへ画素内ずらしを合成した1本である。
fn ずらし付きの射影変換(ずらし: 画素内ずらし) -> 変換<ビュー, クリップ> {
    let 投影: 変換<ビュー, クリップ> = 変換::透視投影(縦視野角(), 横縦比(), メートル::生成する(近クリップ), メートル::生成する(遠クリップ));
    投影.合成する(変換::<クリップ, クリップ>::画素内ずらし(ずらし))
}

/// 正規化装置座標から画素の位置を求める。画面の内側にある点だけを渡す。
fn 正規化装置座標が落ちる画素(寸法: 画像の寸法, 正規化横: f32, 正規化縦: f32) -> (u32, u32) {
    let 横 = (f64::from(正規化横) + 1.0) * 0.5 * f64::from(寸法.幅());
    let 縦 = (f64::from(正規化縦) + 1.0) * 0.5 * f64::from(寸法.高さ());
    (
        crate::numeric::floor_index::実数位置の床の添字(横, 寸法.幅() - 1),
        crate::numeric::floor_index::実数位置の床の添字(縦, 寸法.高さ() - 1),
    )
}

fn 検査する点(横メートル: f32, 縦メートル: f32) -> 位置<ビュー> {
    位置::生成する(メートル::生成する(横メートル), メートル::生成する(縦メートル), メートル::生成する(-4.0))
}

#[test]
fn 深度を書く射影と位置を戻す射影が同じ画素を指す() {
    let ずらし = 検査するずらし();
    let 変換 = ずらし付きの射影変換(ずらし);
    let 復元 = ずらし付きの復元(ずらし);
    let 寸法 = 検査する寸法();
    for (横メートル, 縦メートル) in [(0.0, 0.0), (0.7, 0.3), (-1.2, 0.9), (1.5, -1.1)] {
        let 点 = 検査する点(横メートル, 縦メートル);
        let クリップ位置 = 変換.適用する(点);
        let 期待 = 正規化装置座標が落ちる画素(寸法, クリップ位置.x().値(), クリップ位置.y().値());
        assert_eq!(位置が落ちる画素を求める(復元, 寸法, 点), Some(期待), "点({横メートル}, {縦メートル})");
    }
}

#[test]
fn ずらしを与えても画素と位置は往復する() {
    let 復元 = ずらし付きの復元(検査するずらし());
    let 寸法 = 検査する寸法();
    for (横, 縦) in [(0, 0), (1, 1), (検査する幅 / 2, 検査する高さ / 2), (検査する幅 - 1, 検査する高さ - 1)] {
        let 深度 = 復元.深度へ写す(メートル::生成する(4.0));
        let 位置 = 画素中心の位置を復元する(復元, 寸法, 横, 縦, 深度);
        assert_eq!(位置が落ちる画素を求める(復元, 寸法, 位置), Some((横, 縦)));
    }
}

/// 段1の契約は「既定の絵が1バイトも変わらない」ことであり、その根拠はずらしが零のときに射影も復元も
/// 加える前と同じ値を返すことである。片方でも動けば既存の検収入口の判定値が変わる。
#[test]
fn ずらしが零なら射影も復元も加える前と同じである() {
    let 無ずらし = 画素内ずらし::ずらさない();
    let 投影: 変換<ビュー, クリップ> = 変換::透視投影(縦視野角(), 横縦比(), メートル::生成する(近クリップ), メートル::生成する(遠クリップ));
    assert_eq!(ずらし付きの射影変換(無ずらし), 投影);
    let 寸法 = 検査する寸法();
    let 深度 = 検査する射影().深度へ写す(メートル::生成する(4.0));
    assert_eq!(
        画素中心の位置を復元する(ずらし付きの復元(無ずらし), 寸法, 7, 5, 深度),
        画素中心の位置を復元する(検査する射影(), 寸法, 7, 5, 深度)
    );
}
