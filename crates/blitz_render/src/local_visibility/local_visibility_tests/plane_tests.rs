//! 平面には遮蔽が出ないことを確かめる。担うのは、正対する平面と傾いた平面の両方で全画素が遮蔽なしになることと、
//! その検査が段差では成り立たないことの対である。
//!
//! 平面が自分を遮蔽しないのは幾何の性質である。標本は標点の法線が張る半球の面の上に置かれるため必ず平面より
//! カメラ側にあり、その標本を写した画素の面は標本より奥にある。ここで陰りが出たら、法線の再構成か深度の
//! 下限か射影の往復のどれかが壊れている。

use super::visibility_statistics::地の在る画素の最小可視度;
use super::{傾いた平面, 場面を焼く, 正対する平面, 段差};

#[test]
fn 正対する平面は全画素で遮蔽なしになる() {
    let (深度, 可視度) = 場面を焼く(正対する平面());
    let 最小 = 地の在る画素の最小可視度(&深度, &可視度);
    assert!((最小 - 1.0).abs() < 1.0e-6, "正対する平面に遮蔽が出た(最小可視度{最小})");
}

#[test]
fn 傾いた平面も全画素で遮蔽なしになる() {
    let (深度, 可視度) = 場面を焼く(傾いた平面());
    let 最小 = 地の在る画素の最小可視度(&深度, &可視度);
    assert!((最小 - 1.0).abs() < 1.0e-6, "傾いた平面に遮蔽が出た(最小可視度{最小})");
}

/// 上の2つと同じ検査が段差では落ちることを確かめる。この対が無いと、可視度を常に1にする実装でも
/// 平面の2つは通ってしまう。
#[test]
fn 全画素が遮蔽なしという検査は段差では成り立たない() {
    let (深度, 可視度) = 場面を焼く(段差());
    let 最小 = 地の在る画素の最小可視度(&深度, &可視度);
    assert!(最小 < 1.0 - 1.0e-6, "段差でも遮蔽が1つも出なかった(最小可視度{最小})");
}
