//! 法線の再構成が正しい向きを返すことと、同じ面に載る隣点が無いときに安全に退避することを確かめる。
//! 担うのは、平面の法線の向き、段差の両側で隣点の選び方が働くこと、隣点が1つも使えない画素での退避、
//! そして退避が常には起きないことの対である。
//!
//! 段差の境界の列そのものは退避しない。両隣のうち同じ面に載る側を選ぶ規則があるためであり、
//! この規則が働いていることこそが輪郭で法線が背景へ倒れないことの根拠である。退避が起きるのは、
//! 軸のどちら側にも同じ面に載る隣点が無いときだけである。

use crate::local_visibility::{
    カメラからの奥行き, ビュー空間法線を再構成する, 合成深度を焼く, 法線の再構成結果, 画素が覆う幅を求める, 画素中心の位置を復元する,
};

use super::{
    傾いた平面, 検査する寸法, 検査する射影, 検査する設定, 検査する高さ, 正対する平面, 段差, 段差の境界, 端の段差
};

const 検査する縦: u32 = 検査する高さ / 2;
/// 視線の逆を向いていると認める第三成分の下限。
const 正対とみなす第三成分: f32 = 0.99;

#[test]
fn 正対する平面の法線は視線の逆を向く() {
    let 成分 = 法線の成分(正対する平面(), 20);
    assert!(成分[2] > 正対とみなす第三成分, "正対する平面の法線が視線の逆を向いていない({成分:?})");
}

#[test]
fn 傾いた平面の法線は傾いた向きになる() {
    let 成分 = 法線の成分(傾いた平面(), 20);
    assert!(成分[2] > 0.0, "傾いた平面の法線が視線の側を向いていない({成分:?})");
    assert!(成分[0].abs() > 0.1, "傾いた平面の法線が横へ傾いていない({成分:?})");
}

/// 段差の両側の境界の列で、法線が段差を跨がず自分の面の向きを保つことを確かめる。常に片側の隣点を使う
/// 実装では、どちらか一方の列で法線が段差の向こうへ倒れてこの検査が落ちる。
#[test]
fn 段差の境界の両側でも法線は自分の面の向きを保つ() {
    for 横 in [段差の境界 - 1, 段差の境界] {
        let 成分 = 法線の成分(段差(), 横);
        assert!(成分[2] > 正対とみなす第三成分, "段差の境界の列{横}で法線が倒れた({成分:?})");
    }
}

/// 画面の左端では隣点が片側にしか無い。その唯一の隣点が段差の向こう側にあるとき、面は定まらない。
#[test]
fn 唯一の隣点が段差の向こう側なら面が定まらない() {
    let 深度 = 合成深度を焼く(端の段差(), 検査する寸法(), 検査する射影()).unwrap();
    let 許容 = 検査する設定().遮蔽().同一面の許容();
    let 結果 = ビュー空間法線を再構成する(&深度, 検査する射影(), 許容, 0, 検査する縦);
    assert_eq!(結果, 法線の再構成結果::面が定まらない, "唯一の隣点が段差の向こう側でも面が定まった");
}

/// 上と同じ呼び出しが両隣の使える列では面を返すことを確かめる。この対が無いと、常に退避する実装でも通る。
#[test]
fn 両隣の使える列では面が定まる() {
    let 深度 = 合成深度を焼く(端の段差(), 検査する寸法(), 検査する射影()).unwrap();
    let 許容 = 検査する設定().遮蔽().同一面の許容();
    let 結果 = ビュー空間法線を再構成する(&深度, 検査する射影(), 許容, 20, 検査する縦);
    assert!(matches!(結果, 法線の再構成結果::再構成できた(_)), "両隣の使える列でも面が定まらなかった");
}

/// 段差の高さが1画素の覆う幅の何倍あるかを確かめる。退避の判定は許容倍率との比較であり、
/// この比が許容倍率を超えていない場面では端の列でも退避しない。
#[test]
fn 段差の高さは同一面の許容より十分大きい() {
    let 深度 = 合成深度を焼く(段差(), 検査する寸法(), 検査する射影()).unwrap();
    let 標点 = 画素中心の位置を復元する(検査する射影(), 検査する寸法(), 段差の境界, 検査する縦, 深度.深度(段差の境界, 検査する縦));
    let 覆う幅 = 画素が覆う幅を求める(検査する射影(), 検査する寸法(), カメラからの奥行き(標点));
    let 倍率 = (super::奥の奥行き - super::手前の奥行き) / 覆う幅.値();
    assert!(
        倍率 > 検査する設定().遮蔽().同一面の許容().値(),
        "段差の高さが1画素の覆う幅の{倍率}倍しかなく、許容倍率を超えていない"
    );
}

fn 法線の成分(場面: crate::local_visibility::合成深度の場面, 横: u32) -> [f32; 3] {
    let 深度 = 合成深度を焼く(場面, 検査する寸法(), 検査する射影()).unwrap();
    let 許容 = 検査する設定().遮蔽().同一面の許容();
    let 法線の再構成結果::再構成できた(法線) = ビュー空間法線を再構成する(&深度, 検査する射影(), 許容, 横, 検査する縦)
    else {
        panic!("横{横}で面が定まらなかった");
    };
    法線.成分()
}
