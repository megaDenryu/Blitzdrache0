//! 深度と奥行き、画素とビュー空間の位置の往復が閉じることを確かめる。担うのは、2つの往復と、
//! 画面の外と近クリップより手前の位置が画素を持たないことである。
//!
//! 画面の外が値なしになることは「画像端で画面外を参照しない」という要件そのものである。ここが張り付けを
//! 返すと、画面の縁の画素が端の1列を何度も遮蔽物として数え、縁に暗い帯が出る。

use blitz_math::{ビュー, メートル, 位置};

use crate::local_visibility::{位置が落ちる画素を求める, 画素中心の位置を復元する};

use super::{検査する寸法, 検査する射影, 検査する幅, 検査する高さ};

/// 往復で認める相対の食い違い。深度は奥行きに対して非線形であり、遠クリップ面のすぐ手前では
/// 深度は奥行きに対して非線形であり、遠クリップ面の往復ほど丸めの影響を受ける。
const 往復の相対許容: f32 = 1.0e-3;

#[test]
fn 深度と奥行きは往復する() {
    let 射影 = 検査する射影();
    for 奥行き in [0.1_f32, 1.0, 3.0, 50.0, 10000.0] {
        let 深度 = 射影.深度へ写す(メートル::生成する(奥行き));
        let 戻した = 射影.奥行きを復元する(深度).値();
        assert!(
            (戻した - 奥行き).abs() <= 奥行き * 往復の相対許容,
            "奥行き{奥行き}が{戻した}へ戻った(深度{深度})"
        );
    }
}

#[test]
fn 逆向き深度の端点と単調性を保つ() {
    let 射影 = 検査する射影();
    assert!((射影.深度へ写す(メートル::生成する(0.1)) - 1.0).abs() < 1.0e-6);
    assert!(射影.深度へ写す(メートル::生成する(10000.0)).abs() < 1.0e-6);
    assert!(射影.深度へ写す(メートル::生成する(1.0)) > 射影.深度へ写す(メートル::生成する(10.0)));
}

#[test]
fn 画素と位置は往復する() {
    let 射影 = 検査する射影();
    let 寸法 = 検査する寸法();
    for (横, 縦) in [(0, 0), (1, 1), (検査する幅 / 2, 検査する高さ / 2), (検査する幅 - 1, 検査する高さ - 1)] {
        let 深度 = 射影.深度へ写す(メートル::生成する(4.0));
        let 位置 = 画素中心の位置を復元する(射影, 寸法, 横, 縦, 深度);
        assert_eq!(位置が落ちる画素を求める(射影, 寸法, 位置), Some((横, 縦)));
    }
}

#[test]
fn 画面の外の位置は画素を持たない() {
    let 射影 = 検査する射影();
    let 寸法 = 検査する寸法();
    let 遠く横へ: 位置<ビュー> = 位置::生成する(メートル::生成する(100.0), メートル::生成する(0.0), メートル::生成する(-4.0));
    let 遠く縦へ: 位置<ビュー> = 位置::生成する(メートル::生成する(0.0), メートル::生成する(100.0), メートル::生成する(-4.0));
    assert_eq!(位置が落ちる画素を求める(射影, 寸法, 遠く横へ), None);
    assert_eq!(位置が落ちる画素を求める(射影, 寸法, 遠く縦へ), None);
}

#[test]
fn 近クリップより手前の位置は画素を持たない() {
    let 射影 = 検査する射影();
    let 寸法 = 検査する寸法();
    let 手前: 位置<ビュー> = 位置::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(-0.01));
    let 背後: 位置<ビュー> = 位置::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(1.0));
    assert_eq!(位置が落ちる画素を求める(射影, 寸法, 手前), None);
    assert_eq!(位置が落ちる画素を求める(射影, 寸法, 背後), None);
}
