//! 遮蔽の標本化が読む設定一式。触れる状態を持たず、担うのは5つの量を1組で運ぶことと、
//! 仮置きの初期値をただ1箇所に置くことだけである。
//!
//! 注意: ここの初期値は、絵をまだ1枚も見ていない段階での仮置きである。最終値はGPUへ繋いだ後の
//! オーナーの絵の目視で裁定する(`参照: _doc/設計/放射輝度問い合わせ階層.md`「IIaの実装設計」)。

use blitz_math::メートル;

use super::depth_bias::遮蔽の深度バイアス;
use super::distance_falloff::遮蔽の距離減衰;
use super::occlusion_radius::遮蔽半径;
use super::same_surface_tolerance::同一面の許容倍率;
use super::sample_count::遮蔽の標本数;

/// 遮蔽の標本化の設定。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 遮蔽の設定 {
    半径: 遮蔽半径,
    深度バイアス: 遮蔽の深度バイアス,
    距離減衰: 遮蔽の距離減衰,
    標本数: 遮蔽の標本数,
    同一面の許容: 同一面の許容倍率,
}

impl 遮蔽の設定 {
    pub fn 生成する(
        半径: 遮蔽半径,
        深度バイアス: 遮蔽の深度バイアス,
        距離減衰: 遮蔽の距離減衰,
        標本数: 遮蔽の標本数,
        同一面の許容: 同一面の許容倍率,
    ) -> Self {
        Self {
            半径,
            深度バイアス,
            距離減衰,
            標本数,
            同一面の許容,
        }
    }

    /// 仮置きの初期値。半径0.5メートルは、地形と小物の接地の陰りが数十センチの尺度で起きることによる。
    /// 深度バイアスは1画素が覆う幅の2倍であり、隣の画素の面が標本の手前へ現れる幅を上回る。
    /// 距離減衰は半径までを丸ごと数え、半径の2倍で断ち切る。標本数16は全解像度で回す実時間の基準であり、
    /// 16通りの回転と両側ぼかしを合わせて実効の標本を増やす前提の値である。同一面の許容4倍は、
    /// 画面に対して75度まで傾いた面を同じ面と認める広さにあたる。
    pub fn 既定() -> Self {
        Self::生成する(
            遮蔽半径::生成する(メートル::生成する(0.5)).unwrap_or_else(|誤り| panic!("既定の遮蔽半径が作れない: {誤り}")),
            遮蔽の深度バイアス::生成する(2.0).unwrap_or_else(|誤り| panic!("既定の深度バイアスが作れない: {誤り}")),
            遮蔽の距離減衰::生成する(1.0, 2.0).unwrap_or_else(|誤り| panic!("既定の距離減衰が作れない: {誤り}")),
            遮蔽の標本数::生成する(16).unwrap_or_else(|誤り| panic!("既定の標本数が作れない: {誤り}")),
            同一面の許容倍率::生成する(4.0).unwrap_or_else(|誤り| panic!("既定の同一面の許容が作れない: {誤り}")),
        )
    }

    pub fn 半径(self) -> 遮蔽半径 {
        self.半径
    }

    pub fn 深度バイアス(self) -> 遮蔽の深度バイアス {
        self.深度バイアス
    }

    pub fn 距離減衰(self) -> 遮蔽の距離減衰 {
        self.距離減衰
    }

    pub fn 標本数(self) -> 遮蔽の標本数 {
        self.標本数
    }

    pub fn 同一面の許容(self) -> 同一面の許容倍率 {
        self.同一面の許容
    }
}
