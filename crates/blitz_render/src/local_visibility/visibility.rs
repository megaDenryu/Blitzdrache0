//! 局所可視度という量そのもの。触れる状態を持たず、担うのは値域の保証と、遮蔽の割合から可視度を作る
//! ただ1つの規約を持つことだけである。
//!
//! 遮蔽の側でなく可視度の側を値にするのは、この量が拡散間接照度へ掛かる係数だからである。遮蔽率を持つと
//! 消費側が毎回1から引くことになり、引き忘れが暗い絵でなく明るい絵として現れて気づきにくい。

use super::error::局所可視性エラー;

/// その画素の近傍形状によって拡散間接照度がどれだけ届くかを表す係数。1が遮蔽なしである。
/// 不変条件: 有限かつ0以上1以下である。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 局所可視度 {
    値: f32,
}

impl 局所可視度 {
    pub fn 生成する(値: f32) -> Result<Self, 局所可視性エラー> {
        if !値.is_finite() || !(0.0..=1.0).contains(&値) {
            return Err(局所可視性エラー::値域外("局所可視度", 値));
        }
        Ok(Self { 値 })
    }

    /// 近傍形状が拡散間接照度を1つも遮っていない状態。深度が書かれていない画素と、
    /// 深度の不連続で法線を再構成できない画素がこの値へ退避する。
    pub fn 遮蔽なし() -> Self {
        Self { 値: 1.0 }
    }

    pub fn 値(self) -> f32 {
        self.値
    }

    /// 遮蔽した標本の重みの平均から可視度を作る。標本1件の重みが0以上1以下であるため平均も同じ範囲に入り、
    /// ここでの収容は定義上の値域を外れた値の受け入れではなく、浮動小数の丸めが境界を僅かに越えた分の始末である。
    pub fn 遮蔽の割合から求める(遮蔽の割合: f32) -> Self {
        if !遮蔽の割合.is_finite() {
            panic!("遮蔽の割合が有限でない: {遮蔽の割合}");
        }
        Self {
            値: (1.0 - 遮蔽の割合).clamp(0.0, 1.0),
        }
    }
}
