//! 深度プリパスが書いた画面1枚ぶんの深度をCPU側で保持する値。担うのは全画素の健全性の保証と、
//! 位置1つでの参照と、ジオメトリが描かれていない画素の判別である。
//!
//! 読み戻し画像と別の型にするのは、あちらが読み戻しの結末をそのまま運ぶ器であり、こちらが遮蔽の計算が
//! 依存する不変条件(0以上1以下・有限)を保証する入力だからである。壊れた深度を入れると、出力の壊れが
//! 入力由来か計算由来か見分けられなくなる。

use super::error::局所可視性エラー;
use super::image_size::画像の寸法;

/// 深度プリパスの消去値。この値のままの画素にはジオメトリが1つも描かれていない。
/// 注意: `crates/blitz_render/src/vulkan/graph/depth_attachment.rs`の深度の消去値と同じでなければならない。
/// 違えると空の画素が遮蔽の標本として読まれ、画面全体へ偽の遮蔽が乗る。
pub const 深度の消去値: f32 = 0.0;

/// 深度の全画素。並びは行優先であり、カメラの逆Z規約どおり1が近クリップ面、0が遠クリップ面である。
/// 不変条件: 要素数が寸法の画素数と一致し、全要素が有限かつ0以上1以下である。
#[derive(Debug, Clone, PartialEq)]
pub struct 深度画像 {
    寸法: 画像の寸法,
    深度一覧: Vec<f32>,
}

impl 深度画像 {
    pub fn 生成する(寸法: 画像の寸法, 深度一覧: Vec<f32>) -> Result<Self, 局所可視性エラー> {
        let 期待 = 寸法.画素数();
        if 深度一覧.len() != 期待 {
            return Err(局所可視性エラー::要素数不一致("深度画像", 期待, 深度一覧.len()));
        }
        for 深度 in &深度一覧 {
            if !深度.is_finite() || !(0.0..=1.0).contains(深度) {
                return Err(局所可視性エラー::値域外("深度画像の深度", *深度));
            }
        }
        Ok(Self { 寸法, 深度一覧 })
    }

    pub fn 寸法(&self) -> 画像の寸法 {
        self.寸法
    }

    pub fn 深度(&self, 横: u32, 縦: u32) -> f32 {
        let 通し番号 = self.寸法.通し番号(横, 縦);
        let Some(深度) = self.深度一覧.get(通し番号) else {
            panic!("深度画像の範囲外を参照した(横{横} 縦{縦})");
        };
        *深度
    }

    /// その画素にジオメトリが描かれているか。消去値のままの画素は空であり、遮蔽の標本にも標点にもしない。
    pub fn ジオメトリがあるか(&self, 横: u32, 縦: u32) -> bool {
        self.深度(横, 縦) > 深度の消去値
    }
}
