//! 局所可視性補正のCPU正本のユニットテストを所有するモジュール。担うのは、GPUを起動せずに確かめられる性質
//! (形ごとの可視度の振る舞い・回転の決定性・安全退避の発火・値オブジェクトの拒否)を関心事ごとに束ねることと、
//! どのテストも同じ場面と設定から始められるよう共通の組み立てを1箇所に置くことである。
//!
//! 性質が成り立つことだけを見るテストは、実装が定数を返しても通ってしまう。ここでは性質が破れる入力を対にして
//! 置き、そちらでは実際に落ちることを確かめる(自動露出の純関数層と同じ様式)。
//!
//! GPUと突き合わせる検査はIIa-3が別に持つ。こちらが正本の性質を、あちらが写しの一致を見る。

#![allow(clippy::unwrap_used)]

mod blur_tests;
mod image_value_tests;
mod plane_tests;
mod projection_tests;
mod quantization_tests;
mod rotation_tests;
mod sphere_tests;
mod step_tests;
mod surface_normal_tests;
mod value_object_tests;
mod visibility_statistics;

use blitz_math::{メートル, ラジアン};

use super::narrowing::整数を単精度へ狭める;
use super::{
    合成深度の場面, 合成深度を焼く, 射影の復元, 局所可視度画像, 局所可視度画像を焼く, 局所可視性の設定, 深度画像, 画像の寸法
};

/// 検収の場面が使う画面の寸法。遮蔽半径が画面の一部だけを覆う広さと、テストの実行時間の釣り合いによる。
pub(super) const 検査する幅: u32 = 96;
pub(super) const 検査する高さ: u32 = 72;
/// 段差の境界を置く横位置。左右のどちらの側にも遮蔽半径ぶんの余白が残る位置である。
pub(super) const 段差の境界: u32 = 48;
/// 場面の代表の奥行き。1画素が覆う幅がこの奥行きで約0.048メートルであり、遮蔽半径0.5メートルは約10画素にあたる。
pub(super) const 手前の奥行き: f32 = 3.0;
pub(super) const 奥の奥行き: f32 = 3.5;

pub(super) fn 検査する射影() -> 射影の復元 {
    射影の復元::生成する(
        メートル::生成する(0.1),
        メートル::生成する(2000.0),
        ラジアン::生成する(std::f32::consts::FRAC_PI_3),
        整数を単精度へ狭める(検査する幅) / 整数を単精度へ狭める(検査する高さ),
    )
    .unwrap()
}

pub(super) fn 検査する寸法() -> 画像の寸法 {
    画像の寸法::生成する(検査する幅, 検査する高さ).unwrap()
}

pub(super) fn 検査する設定() -> 局所可視性の設定 {
    局所可視性の設定::既定()
}

pub(super) fn 正対する平面() -> 合成深度の場面 {
    合成深度の場面::平面(メートル::生成する(手前の奥行き), 0.0).unwrap()
}

pub(super) fn 傾いた平面() -> 合成深度の場面 {
    合成深度の場面::平面(メートル::生成する(手前の奥行き), 0.5).unwrap()
}

pub(super) fn 段差() -> 合成深度の場面 {
    合成深度の場面::段差(メートル::生成する(手前の奥行き), メートル::生成する(奥の奥行き), 段差の境界).unwrap()
}

/// 段差の境界を画面の左端の隣へ置いた場面。左端の列は唯一の隣点が段差の向こう側になる。
pub(super) fn 端の段差() -> 合成深度の場面 {
    合成深度の場面::段差(メートル::生成する(手前の奥行き), メートル::生成する(奥の奥行き), 1).unwrap()
}

pub(super) fn 球() -> 合成深度の場面 {
    合成深度の場面::球(メートル::生成する(手前の奥行き), メートル::生成する(1.0)).unwrap()
}

/// 場面から深度画像と、既定の設定で焼いた局所可視度画像の対を作る。
pub(super) fn 場面を焼く(場面: 合成深度の場面) -> (深度画像, 局所可視度画像) {
    場面を設定で焼く(場面, 検査する設定())
}

pub(super) fn 場面を設定で焼く(場面: 合成深度の場面, 設定: 局所可視性の設定) -> (深度画像, 局所可視度画像) {
    let 深度 = 合成深度を焼く(場面, 検査する寸法(), 検査する射影()).unwrap();
    let 可視度 = 局所可視度画像を焼く(&深度, 検査する射影(), 設定);
    (深度, 可視度)
}
