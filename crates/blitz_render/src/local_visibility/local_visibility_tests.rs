//! 局所可視性補正のCPU正本のユニットテストを所有するモジュール。担うのは、GPUを起動せずに確かめられる性質
//! (形ごとの可視度の振る舞い・回転の決定性・安全退避の発火・値オブジェクトの拒否)を関心事ごとに束ねることと、
//! どのテストも同じ場面と設定から始められるよう共通の組み立てを1箇所に置くことである。
//!
//! 性質が成り立つことだけを見るテストは、実装が定数を返しても通ってしまう。ここでは性質が破れる入力を対にして
//! 置き、そちらでは実際に落ちることを確かめる(自動露出の純関数層と同じ様式)。
//!
//! GPUと突き合わせる検査はIIa-3が別に持つ。こちらが正本の性質を、あちらが写しの一致を見る。

