//! 生の局所可視度を、同じ面に載る画素の間だけで均す工程。受け取るのは生の可視度画像と深度画像と射影と設定、
//! 返すのは均した後の可視度画像である。
//!
//! 均しが要るのは、標本の方位を画素ごとに回してあるためである。回転で散らした偏りは1画素だけを見ると
//! 雑音として残り、隣り合う画素をまとめて初めて打ち消し合う。
//!
//! 面をまたいで均さない判定に、標点の法線が張る平面からの距離を使う。奥行きの差だけで判定すると、
//! 斜めから見た床が奥行きの差だけで別の面と見なされ、床の陰りが均されないまま雑音を残す。
//!
//! 窓の中の重みを等しくするのは、定義が1つに定まることを優先したためである。中央を厚くする重みへ替えても
//! 均す対象は変わらないため、絵の裁定で必要になったときの差し替えは局所で済む。

use super::depth_image::深度画像;
use super::narrowing::整数を単精度へ狭める;
use super::normal_reconstruction::{ビュー空間法線を再構成する, 法線の再構成結果};
use super::projection::射影の復元;
use super::settings::局所可視性の設定;
use super::view_displacement::ビュー空間の変位;
use super::view_position::{カメラからの奥行き, 画素が覆う幅を求める, 画素中心の位置を復元する};
use super::visibility::局所可視度;
use super::visibility_image::局所可視度画像;

/// 両側ぼかしを掛けた局所可視度画像。
/// 前提: 生の可視度画像と深度画像は同じ寸法である。
pub fn 両側ぼかしを掛ける(
    生の可視度: &局所可視度画像,
    深度画像: &深度画像,
    射影: 射影の復元,
    設定: 局所可視性の設定,
) -> 局所可視度画像 {
    let 寸法 = 深度画像.寸法();
    let mut 均した = Vec::with_capacity(寸法.画素数());
    for 縦 in 0..寸法.高さ() {
        for 横 in 0..寸法.幅() {
            均した.push(画素を均す(生の可視度, 深度画像, 射影, 設定, 横, 縦));
        }
    }
    局所可視度画像::生成する(寸法, 均した).unwrap_or_else(|誤り| panic!("均した可視度の並びが寸法と合わない: {誤り}"))
}

/// 画素1つの均した可視度。深度が書かれていない画素は遮蔽なし、面が定まらない画素は生の値をそのまま返す。
fn 画素を均す(
    生の可視度: &局所可視度画像, 深度画像: &深度画像, 射影: 射影の復元, 設定: 局所可視性の設定, 横: u32, 縦: u32
) -> 局所可視度 {
    if !深度画像.ジオメトリがあるか(横, 縦) {
        return 局所可視度::遮蔽なし();
    }
    let 標点 = 画素中心の位置を復元する(射影, 深度画像.寸法(), 横, 縦, 深度画像.深度(横, 縦));
    let 法線の再構成結果::再構成できた(法線) = ビュー空間法線を再構成する(深度画像, 射影, 設定.遮蔽().同一面の許容(), 横, 縦)
    else {
        return 生の可視度.可視度(横, 縦);
    };
    let 覆う幅 = 画素が覆う幅を求める(射影, 深度画像.寸法(), カメラからの奥行き(標点));
    let 許容 = 設定.ぼかし().同じ面と認める許容().距離の上限(覆う幅);
    let 半径 = i64::from(設定.ぼかし().画素半径());
    let mut 和 = 0.0_f32;
    let mut 件数 = 0_u32;
    for 縦ずれ in -半径..=半径 {
        for 横ずれ in -半径..=半径 {
            let Some((近傍の横, 近傍の縦)) = 窓の中の画素(深度画像, 横, 縦, 横ずれ, 縦ずれ) else {
                continue;
            };
            let 近傍 = 画素中心の位置を復元する(射影, 深度画像.寸法(), 近傍の横, 近傍の縦, 深度画像.深度(近傍の横, 近傍の縦));
            let 平面からの距離 = ビュー空間の変位::位置の差から(近傍, 標点).向きへの射影(法線).値().abs();
            if 平面からの距離 > 許容.値() {
                continue;
            }
            和 += 生の可視度.可視度(近傍の横, 近傍の縦).値();
            件数 += 1;
        }
    }
    平均を可視度にする(和, 件数)
}

/// 窓の中の画素のうち、画面に収まりジオメトリが描かれているものだけを返す。
fn 窓の中の画素(深度画像: &深度画像, 横: u32, 縦: u32, 横ずれ: i64, 縦ずれ: i64) -> Option<(u32, u32)> {
    let 近傍の横 = u32::try_from(i64::from(横) + 横ずれ).ok()?;
    let 近傍の縦 = u32::try_from(i64::from(縦) + 縦ずれ).ok()?;
    if !深度画像.寸法().含むか(近傍の横, 近傍の縦) || !深度画像.ジオメトリがあるか(近傍の横, 近傍の縦) {
        return None;
    }
    Some((近傍の横, 近傍の縦))
}

/// 中心の画素は必ず窓を通るため件数は1以上になる。0件はこの前提が破れたことを意味する。
fn 平均を可視度にする(和: f32, 件数: u32) -> 局所可視度 {
    if 件数 == 0 {
        panic!("両側ぼかしの窓が中心の画素すら通していない");
    }
    let 平均 = (和 / 整数を単精度へ狭める(件数)).clamp(0.0, 1.0);
    局所可視度::生成する(平均).unwrap_or_else(|誤り| panic!("均した可視度が値域を外れた: {誤り}"))
}
