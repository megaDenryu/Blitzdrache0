//! 局所可視性補正の資源を作るのに要る材料。触れる状態を持たず、担うのは数値の設定と世界の宣言と検収の上書きを1組で運ぶことと、
//! その3つからパスを積むかどうかと2枚の画像を埋める符号値を導くことである。
//!
//! 拡散間接方式が環境のみでも受け取るのは、資源の有無を方式で分けると照明問い合わせのセットが世界ごとに違う形になり、
//! 束縛の一致条件が1つ増えるためである。パスを積むかどうかだけが方式と上書きで分かれる。

use super::acceptance_override::局所可視度の上書き;
use super::code_value::局所可視度の符号値;
use super::diffuse_indirect_method::拡散間接方式;
use super::settings::局所可視性の設定;
use super::visibility::局所可視度;

/// 局所可視性補正の描画側の設定。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 局所可視性の描画設定 {
    /// 遮蔽の標本化と両側ぼかしが読む数値の設定。正本はCPU側の純関数層が持つ。
    pub 補正の設定: 局所可視性の設定,
    pub 方式: 拡散間接方式,
    /// 検収が局所可視度を一定値へ固定する上書き。本番の起動は`上書きしない`である。
    pub 検収の上書き: 局所可視度の上書き,
}

impl 局所可視性の描画設定 {
    /// 遮蔽の標本化と両側ぼかしをそのフレームへ積むか。環境のみの世界と、検収が値を固定した実行では1本も積まない。
    pub(crate) fn パスを積むか(self) -> bool {
        match self.検収の上書き {
            局所可視度の上書き::上書きしない => self.方式.パスを積むか(),
            局所可視度の上書き::固定符号値(_) => false,
        }
    }

    /// 2枚の画像を確保した直後に埋める符号値。上書きしない実行は遮蔽なしで埋める。
    /// 環境のみの世界ではこの値が最後まで残り、符号値255はちょうど1.0であるため拡散間接照度を1ビットも変えない。
    pub(crate) fn 埋める符号値(self) -> 局所可視度の符号値 {
        match self.検収の上書き {
            局所可視度の上書き::上書きしない => 局所可視度の符号値::量子化する(局所可視度::遮蔽なし()),
            局所可視度の上書き::固定符号値(符号値) => 符号値,
        }
    }
}
