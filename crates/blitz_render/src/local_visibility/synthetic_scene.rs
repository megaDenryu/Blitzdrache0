//! 検収が深度画像を組み立てるために名指しする形。触れる状態を持たず、担うのは4つの形の値域の保証と、
//! 形ごとの寸法を1つの値へ束ねることだけである。
//!
//! 実物のシーンでなくこの4つを検収の入力にするのは、局所可視度の期待される振る舞いが形そのものから
//! 言えるためである。平面は遮蔽が起きない形、段差は片側だけが暗くなる形、球は凸で偽の遮蔽が出ない形、
//! 凹面は法線が連続に変わりながら遮蔽が生まれる形であり、実物のシーンを撮った深度からはこの4つの性質を
//! 分けて読めない。生成を関数に閉じて内側の判別を外へ出さないのは、値域を確かめずに組み立てた形を
//! 焼かせないためである。

use blitz_math::{メートル, 逆メートル};

use super::error::局所可視性エラー;
use super::scene_shape::場面の形;

/// 検収が焼かせる深度の形。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 合成深度の場面 {
    形: 場面の形,
}

impl 合成深度の場面 {
    /// 画面いっぱいの平面。横の傾きは、横のビュー座標が1メートル増えるごとに奥行きが増える割合である。
    /// 0なら視線に正対する。
    pub fn 平面(中心の奥行き: メートル, 横の傾き: f32) -> Result<Self, 局所可視性エラー> {
        正の長さであること("平面の中心の奥行き", 中心の奥行き)?;
        if !横の傾き.is_finite() || 横の傾き.abs() >= 1.0 {
            return Err(局所可視性エラー::値域外("平面の横の傾き", 横の傾き));
        }
        Ok(Self::包む(場面の形::平面 {
            中心の奥行き, 横の傾き
        }))
    }

    /// 境界の左が手前、右が奥の2枚の正対する平面。奥の側の境界寄りが接触側であり、手前の側が凸側である。
    pub fn 段差(
        手前の奥行き: メートル, 奥の奥行き: メートル, 境界の横位置: u32
    ) -> Result<Self, 局所可視性エラー> {
        正の長さであること("段差の手前の奥行き", 手前の奥行き)?;
        正の長さであること("段差の奥の奥行き", 奥の奥行き)?;
        if 奥の奥行き.値() <= 手前の奥行き.値() {
            return Err(局所可視性エラー::上下の順序が逆(
                "段差の奥行き",
                手前の奥行き.値(),
                奥の奥行き.値(),
            ));
        }
        Ok(Self::包む(場面の形::段差 {
            手前の奥行き,
            奥の奥行き,
            境界の横位置,
        }))
    }

    /// 視線の上に中心を置いた球。周りは空であり、そこには深度が書かれない。
    pub fn 球(中心の奥行き: メートル, 半径: メートル) -> Result<Self, 局所可視性エラー> {
        正の長さであること("球の中心の奥行き", 中心の奥行き)?;
        正の長さであること("球の半径", 半径)?;
        if 半径.値() >= 中心の奥行き.値() {
            return Err(局所可視性エラー::上下の順序が逆(
                "球の半径と中心の奥行き",
                半径.値(),
                中心の奥行き.値(),
            ));
        }
        Ok(Self::包む(場面の形::球 { 中心の奥行き, 半径 }))
    }

    /// 視線の軸を底に持ち、軸から離れるほど縁がカメラの側へ立ち上がる二次曲面。奥行きは底の奥行きから、
    /// 軸までの距離の二乗に曲率を掛けた分だけ減る。曲率の次元が逆長さであるため、この積は長さになる。
    pub fn 凹面(底の奥行き: メートル, 曲率: 逆メートル) -> Result<Self, 局所可視性エラー> {
        正の長さであること("凹面の底の奥行き", 底の奥行き)?;
        if !曲率.値().is_finite() || 曲率.値() <= 0.0 {
            return Err(局所可視性エラー::値域外("凹面の曲率", 曲率.値()));
        }
        Ok(Self::包む(場面の形::凹面 { 底の奥行き, 曲率 }))
    }

    pub(super) fn 形(self) -> 場面の形 {
        self.形
    }

    fn 包む(形: 場面の形) -> Self {
        Self { 形 }
    }
}

fn 正の長さであること(項目: &'static str, 長さ: メートル) -> Result<(), 局所可視性エラー> {
    if !長さ.値().is_finite() || 長さ.値() <= 0.0 {
        return Err(局所可視性エラー::値域外(項目, 長さ.値()));
    }
    Ok(())
}
