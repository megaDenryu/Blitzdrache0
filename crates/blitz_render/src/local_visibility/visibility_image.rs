//! 画面1枚ぶんの局所可視度をCPU側で保持する値。担うのは全画素の健全性の保証と、位置1つでの参照と、
//! GPUの画像形式へ量子化した並びを返すことである。
//!
//! 生のAOの画像とぼかした後の画像が同じ型を共有するのは、2つが同じ量を同じ寸法で持つためである。
//! 別の型にすると、ぼかしの入力へぼかし後の画像を渡す誤りは型で止まるが、代わりに同じ検査を2度書くことになる。
//! 順序の誤りは工程の引数の名前と焼き上げの順序が守る。

use super::code_value::局所可視度の符号値;
use super::error::局所可視性エラー;
use super::image_size::画像の寸法;
use super::visibility::局所可視度;

/// 局所可視度の全画素。並びは行優先である。
/// 不変条件: 要素数が寸法の画素数と一致する(各要素の値域は要素の型が保つ)。
#[derive(Debug, Clone, PartialEq)]
pub struct 局所可視度画像 {
    寸法: 画像の寸法,
    可視度一覧: Vec<局所可視度>,
}

impl 局所可視度画像 {
    pub fn 生成する(寸法: 画像の寸法, 可視度一覧: Vec<局所可視度>) -> Result<Self, 局所可視性エラー> {
        let 期待 = 寸法.画素数();
        if 可視度一覧.len() != 期待 {
            return Err(局所可視性エラー::要素数不一致("局所可視度画像", 期待, 可視度一覧.len()));
        }
        Ok(Self { 寸法, 可視度一覧 })
    }

    pub fn 寸法(&self) -> 画像の寸法 {
        self.寸法
    }

    pub fn 可視度(&self, 横: u32, 縦: u32) -> 局所可視度 {
        let 通し番号 = self.寸法.通し番号(横, 縦);
        let Some(可視度) = self.可視度一覧.get(通し番号) else {
            panic!("局所可視度画像の範囲外を参照した(横{横} 縦{縦})");
        };
        *可視度
    }

    pub fn 可視度一覧(&self) -> &[局所可視度] {
        &self.可視度一覧
    }

    /// GPUの8ビット無符号正規化形式へ量子化した並び。読み戻した画像との突き合わせがこの並びを比べる。
    pub fn 符号値列(&self) -> Vec<u8> {
        self.可視度一覧
            .iter()
            .map(|可視度| 局所可視度の符号値::量子化する(*可視度).値())
            .collect()
    }
}
