//! 画素の位置から決定的な整数を混ぜ合わせる工程。受け取るのは画素の横と縦の位置、返すのは
//! 位置が1つ違えば大きく離れる32ビットの整数である。
//!
//! 正弦を使う混ぜ方を採らないのは、超越関数の近似が機材ごとに違い、同じ画素が機材によって別の回転を
//! 選ぶためである。整数の乗算とビットずらしだけなら、どの機材でも同じ答えが出る。
//!
//! 乗数は奇数であり、32ビットの乗算に対して逆元を持つ。偶数を使うと下位のビットが必ず0になり、
//! 混ぜた結果の下位から回転を選ぶと本数の一部しか現れない。

/// 横の位置に掛ける奇数。黄金比の逆数を32ビットへ写した値であり、隣り合う位置を最も離す。
const 横の乗数: u32 = 0x9E37_79B1;
/// 縦の位置に掛ける奇数。横の乗数と互いに素な別の混ぜ合わせを与える。
const 縦の乗数: u32 = 0x85EB_CA77;
/// 混ぜ合わせの段で掛ける奇数の組。上位のビットを下位へ折り返しながら乗算を挟む。
const 混ぜの乗数: [u32; 2] = [0x2C1B_3C6D, 0x297A_2D39];
/// 折り返しのずらし幅。
const 折り返しのずらし: [u32; 3] = [15, 13, 16];

/// 画素の位置から決まる整数。同じ位置なら必ず同じ値を返す。
pub fn 画素位置の整数ハッシュ(横: u32, 縦: u32) -> u32 {
    let mut 値 = 横.wrapping_mul(横の乗数) ^ 縦.wrapping_mul(縦の乗数);
    値 ^= 値 >> 折り返しのずらし[0];
    値 = 値.wrapping_mul(混ぜの乗数[0]);
    値 ^= 値 >> 折り返しのずらし[1];
    値 = 値.wrapping_mul(混ぜの乗数[1]);
    値 ^= 値 >> 折り返しのずらし[2];
    値
}
