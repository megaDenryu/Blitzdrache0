//! 両側ぼかしが読む設定一式。触れる状態を持たず、担うのは窓の広さの値域の保証と、仮置きの初期値を
//! ただ1箇所に置くことだけである。
//!
//! 窓の広さを画素で持つのは、ぼかしが標本の回転の違いを均す工程であり、その回転が画素の位置で決まるためである。
//! 世界の長さで持つと、同じ回転の並びを覆うのに要る画素数がカメラの距離で変わる。
//!
//! 注意: ここの初期値は仮置きである。最終値はGPUへ繋いだ後のオーナーの絵の目視で裁定する
//! (`参照: _doc/設計/放射輝度問い合わせ階層.md`「IIaの実装設計」)。

use super::error::局所可視性エラー;
use super::same_surface_tolerance::同一面の許容倍率;

/// 誤った桁の設定を止めるための窓の広さの上限。
const 画素半径の上限: u32 = 16;

/// 両側ぼかしの設定。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 両側ぼかしの設定 {
    画素半径: u32,
    同じ面と認める許容: 同一面の許容倍率,
}

impl 両側ぼかしの設定 {
    pub fn 生成する(画素半径: u32, 同じ面と認める許容: 同一面の許容倍率) -> Result<Self, 局所可視性エラー> {
        if 画素半径 == 0 || 画素半径 > 画素半径の上限 {
            return Err(局所可視性エラー::整数値域外("ぼかしの画素半径", 画素半径));
        }
        Ok(Self {
            画素半径,
            同じ面と認める許容,
        })
    }

    /// 仮置きの初期値。画素半径2の窓は25画素を覆い、16通りの回転をどの向きへ寄せても窓の中に
    /// 全通りが入りうる広さになる。同一面の許容2倍は、窓の端の画素が中心の面から離れてよい距離を
    /// 1画素が覆う幅の2つぶんに切り、段差を跨いで濃さを混ぜないための幅である。
    pub fn 既定() -> Self {
        let 許容 = 同一面の許容倍率::生成する(2.0).unwrap_or_else(|誤り| panic!("既定のぼかしの許容が作れない: {誤り}"));
        Self::生成する(2, 許容).unwrap_or_else(|誤り| panic!("既定の両側ぼかしの設定が作れない: {誤り}"))
    }

    pub fn 画素半径(self) -> u32 {
        self.画素半径
    }

    pub fn 同じ面と認める許容(self) -> 同一面の許容倍率 {
        self.同じ面と認める許容
    }
}
