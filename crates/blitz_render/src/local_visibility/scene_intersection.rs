//! 名指しした形と視線1本の交わりを求める工程。受け取るのは形と視線の向きと画素の横位置、返すのは
//! 交わる点のカメラからの奥行き、または当たらないという答えである。
//!
//! 走査と深度への写しから分けるのは、この工程だけが形ごとの解析解を持つためである。形を1つ足すときに
//! 触るのはここだけであり、画面の走り方も視錐台の切り方も動かさずに済む。
//!
//! 視線は正規化せず奥の成分を-1に固定した形で受ける。この形なら横と縦の成分がそのまま奥行き1メートル
//! あたりのビュー空間の広がりを表し、平面と凹面の解が奥行きの一次式と二次式で直に書ける。

use blitz_math::{メートル, 逆メートル};

use super::scene_shape::場面の形;

/// 視線がその形に当たる奥行き。当たらなければ値なしである。
pub(super) fn 形と視線の交わりの奥行き(形: 場面の形, 視線: [f32; 3], 横: u32) -> Option<メートル> {
    match 形 {
        場面の形::平面 {
            中心の奥行き, 横の傾き
        } => 平面の奥行き(中心の奥行き, 横の傾き, 視線),
        場面の形::段差 {
            手前の奥行き,
            奥の奥行き,
            境界の横位置,
        } => Some(if 横 < 境界の横位置 { 手前の奥行き } else { 奥の奥行き }),
        場面の形::球 { 中心の奥行き, 半径 } => 球の奥行き(中心の奥行き, 半径, 視線),
        場面の形::凹面 { 底の奥行き, 曲率 } => 凹面の奥行き(底の奥行き, 曲率, 視線),
    }
}

/// 奥行きが横のビュー座標に比例して増える平面との交わり。視線が平面と平行に近い側では当たらない。
fn 平面の奥行き(中心の奥行き: メートル, 横の傾き: f32, 視線: [f32; 3]) -> Option<メートル> {
    let 分母 = 1.0 - 横の傾き * 視線[0];
    if !分母.is_finite() || 分母 <= 0.0 {
        return None;
    }
    Some(メートル::生成する(中心の奥行き.値() / 分母))
}

/// 視線の上に中心を置いた球との、手前側の交わり。
fn 球の奥行き(中心の奥行き: メートル, 半径: メートル, 視線: [f32; 3]) -> Option<メートル> {
    let 視線の長さ = 視線の長さを求める(視線);
    let 単位視線 = [視線[0] / 視線の長さ, 視線[1] / 視線の長さ, 視線[2] / 視線の長さ];
    let 中心までの内積 = -単位視線[2] * 中心の奥行き.値();
    let 判別式 = 中心までの内積 * 中心までの内積 - (中心の奥行き.値() * 中心の奥行き.値() - 半径.値() * 半径.値());
    if !判別式.is_finite() || 判別式 < 0.0 {
        return None;
    }
    let 距離 = 中心までの内積 - 判別式.sqrt();
    if 距離 <= 0.0 {
        return None;
    }
    Some(メートル::生成する(距離 / 視線の長さ))
}

/// 二次曲面との交わり。奥行きをtとすると軸までの距離はtに視線の横縦の長さを掛けた値であり、
/// 面の式は`t = 底 - 曲率 * t^2 * (横^2 + 縦^2)`になる。tの二次方程式の正の根が交わる点である。
fn 凹面の奥行き(底の奥行き: メートル, 曲率: 逆メートル, 視線: [f32; 3]) -> Option<メートル> {
    let 軸からの広がり = 視線[0] * 視線[0] + 視線[1] * 視線[1];
    let 二次の係数 = 曲率.値() * 軸からの広がり;
    if 二次の係数 <= 0.0 {
        return Some(底の奥行き);
    }
    let 判別式 = 1.0 + 4.0 * 二次の係数 * 底の奥行き.値();
    if !判別式.is_finite() || 判別式 < 0.0 {
        return None;
    }
    Some(メートル::生成する((判別式.sqrt() - 1.0) / (2.0 * 二次の係数)))
}

fn 視線の長さを求める(視線: [f32; 3]) -> f32 {
    (視線[0] * 視線[0] + 視線[1] * 視線[1] + 視線[2] * 視線[2]).sqrt()
}
