//! 深度画像1枚から局所可視度画像1枚を作るまでの工程の並び。受け取るのは深度画像と射影と設定、
//! 返すのは均した後の局所可視度画像である。
//!
//! この並びがGPU側のパスの構成の正本である。遮蔽の標本化1つとぼかし1つの2工程であり、
//! 間に置く画像は生の可視度の1枚だけである。ぼかしを水平と垂直へ分けて3工程にしない理由は3つある。
//!
//! 第一に、両側の重みは中心の画素の面で決まるため、分けた2工程の合成は2次元1回と別の演算になり、
//! しかもどちらの向きを先に掛けたかで結果が変わる。正本が定義する演算を写しがそのまま踏めるほうが、
//! 一致検査の対象が1つに定まる。第二に、既定の窓は5画素四方の25標本であり、分けた場合の10標本との差は
//! 1画素1バイトの画像への読み出し15回にすぎない。第三に、分けると中間の画像が1枚増え、
//! レンダーグラフの用途遷移とパスの本数もそれぞれ1つ増える。
//!
//! 窓をこれより大きく取る裁定が出たときは、標本数の差が広がるため分離を選び直す余地がある。
//! その差し替えはこのファイルの工程の並びとGPU側のパスの積み方に閉じる。

use super::bilateral_blur::両側ぼかしを掛ける;
use super::depth_image::深度画像;
use super::occlusion_sampling::画素の局所可視度を求める;
use super::occlusion_settings::遮蔽の設定;
use super::projection::射影の復元;
use super::settings::局所可視性の設定;
use super::visibility_image::局所可視度画像;

/// ぼかす前の局所可視度画像。GPU側では中間の1枚へ書き出される内容である。
pub fn 生の局所可視度を焼く(深度画像: &深度画像, 射影: 射影の復元, 設定: 遮蔽の設定) -> 局所可視度画像 {
    let 寸法 = 深度画像.寸法();
    let mut 可視度一覧 = Vec::with_capacity(寸法.画素数());
    for 縦 in 0..寸法.高さ() {
        for 横 in 0..寸法.幅() {
            可視度一覧.push(画素の局所可視度を求める(深度画像, 射影, 設定, 横, 縦));
        }
    }
    局所可視度画像::生成する(寸法, 可視度一覧).unwrap_or_else(|誤り| panic!("生の可視度の並びが寸法と合わない: {誤り}"))
}

/// 2工程を通した局所可視度画像。拡散間接照度へ掛かるのはこの画像である。
pub fn 局所可視度画像を焼く(
    深度画像: &深度画像, 射影: 射影の復元, 設定: 局所可視性の設定
) -> 局所可視度画像 {
    let 生 = 生の局所可視度を焼く(深度画像, 射影, 設定.遮蔽());
    両側ぼかしを掛ける(&生, 深度画像, 射影, 設定)
}
