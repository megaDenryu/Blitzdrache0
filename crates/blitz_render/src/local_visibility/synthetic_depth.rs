//! 名指しした形から深度画像1枚を組み立てる工程。受け取るのは形と寸法と射影、返すのは深度画像である。
//!
//! この工程はCPU正本の検査とGPUへの注入の両方が同じ1つを使う。検収の側が別に深度を組み立てると、
//! 正本と写しの差に「与えた形の違い」が混ざり、写しの誤りだけを取り出せなくなる。
//!
//! 近クリップ面より手前と遠クリップ面より奥へ落ちた点には深度を書かない。実際の描画でも視錐台の外は
//! 描かれず、消去値のまま残るためである。

use blitz_math::メートル;

use super::depth_image::{深度の消去値, 深度画像};
use super::error::局所可視性エラー;
use super::image_size::画像の寸法;
use super::projection::射影の復元;
use super::synthetic_scene::{合成深度の場面, 場面の形};
use super::view_position::画素中心の正規化装置座標;

/// 形が作る深度画像。
pub fn 合成深度を焼く(
    場面: 合成深度の場面, 寸法: 画像の寸法, 射影: 射影の復元
) -> Result<深度画像, 局所可視性エラー> {
    let mut 深度一覧 = Vec::with_capacity(寸法.画素数());
    for 縦 in 0..寸法.高さ() {
        for 横 in 0..寸法.幅() {
            let 視線 = 画素中心の視線方向(射影, 寸法, 横, 縦);
            let 奥行き = 形の奥行き(場面.形(), 視線, 横);
            深度一覧.push(深度へ写す(射影, 奥行き));
        }
    }
    深度画像::生成する(寸法, 深度一覧)
}

/// 画素の中心を通る視線の向き。正規化せず、奥の成分を-1に固定した形で返す。
fn 画素中心の視線方向(射影: 射影の復元, 寸法: 画像の寸法, 横: u32, 縦: u32) -> [f32; 3] {
    let [正規化横, 正規化縦] = 画素中心の正規化装置座標(寸法, 横, 縦);
    [
        正規化横 * 射影.縦視野角の半角の正接() * 射影.横縦比(),
        -正規化縦 * 射影.縦視野角の半角の正接(),
        -1.0,
    ]
}

/// 視線がその形に当たる奥行き。当たらなければ値なしである。
fn 形の奥行き(形: 場面の形, 視線: [f32; 3], 横: u32) -> Option<メートル> {
    match 形 {
        場面の形::平面 {
            中心の奥行き, 横の傾き
        } => 平面の奥行き(中心の奥行き, 横の傾き, 視線),
        場面の形::段差 {
            手前の奥行き,
            奥の奥行き,
            境界の横位置,
        } => Some(if 横 < 境界の横位置 { 手前の奥行き } else { 奥の奥行き }),
        場面の形::球 { 中心の奥行き, 半径 } => 球の奥行き(中心の奥行き, 半径, 視線),
    }
}

/// 奥行きが横のビュー座標に比例して増える平面との交わり。視線が平面と平行に近い側では当たらない。
fn 平面の奥行き(中心の奥行き: メートル, 横の傾き: f32, 視線: [f32; 3]) -> Option<メートル> {
    let 分母 = 1.0 - 横の傾き * 視線[0];
    if !分母.is_finite() || 分母 <= 0.0 {
        return None;
    }
    Some(メートル::生成する(中心の奥行き.値() / 分母))
}

/// 視線の上に中心を置いた球との、手前側の交わり。
fn 球の奥行き(中心の奥行き: メートル, 半径: メートル, 視線: [f32; 3]) -> Option<メートル> {
    let 視線の長さ = (視線[0] * 視線[0] + 視線[1] * 視線[1] + 視線[2] * 視線[2]).sqrt();
    let 単位視線 = [視線[0] / 視線の長さ, 視線[1] / 視線の長さ, 視線[2] / 視線の長さ];
    let 中心までの内積 = -単位視線[2] * 中心の奥行き.値();
    let 判別式 = 中心までの内積 * 中心までの内積 - (中心の奥行き.値() * 中心の奥行き.値() - 半径.値() * 半径.値());
    if !判別式.is_finite() || 判別式 < 0.0 {
        return None;
    }
    let 距離 = 中心までの内積 - 判別式.sqrt();
    if 距離 <= 0.0 {
        return None;
    }
    Some(メートル::生成する(距離 / 視線の長さ))
}

/// 視錐台の内側にある奥行きだけを深度へ写す。外側と当たらなかった画素は消去値のままである。
fn 深度へ写す(射影: 射影の復元, 奥行き: Option<メートル>) -> f32 {
    let Some(奥行き) = 奥行き else { return 深度の消去値 };
    let 深度 = 射影.深度へ写す(奥行き);
    if !深度.is_finite() || !(0.0..深度の消去値).contains(&深度) {
        return 深度の消去値;
    }
    深度
}
