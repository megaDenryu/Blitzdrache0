//! ビュー空間の2点を結ぶ変位という量そのもの。触れる状態を持たず、担うのは長さの次元を保った成分の保持と、
//! 位置との足し引き、長さ、単位の向きへの正規化である。
//!
//! 位置を`blitz_math`のフレーム型で持ちながら変位をここへ置くのは、ビュー空間のベクトル代数の利用者が
//! 現在この木しか無いためである。2つ目の利用者が現れたときに`blitz_math`へ昇格させる余地は閉じていない。

use blitz_math::{ビュー, メートル, 位置};

use super::view_direction::ビュー空間の向き;

/// ビュー空間の変位。成分の並びは横・縦・奥であり、単位はメートルである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ビュー空間の変位 {
    成分: [f32; 3],
}

impl ビュー空間の変位 {
    pub fn 生成する(横: メートル, 縦: メートル, 奥: メートル) -> Self {
        Self {
            成分: [横.値(), 縦.値(), 奥.値()],
        }
    }

    /// 始点から終点へ向かう変位。
    pub fn 位置の差から(終点: 位置<ビュー>, 始点: 位置<ビュー>) -> Self {
        Self::生成する(終点.x() - 始点.x(), 終点.y() - 始点.y(), 終点.z() - 始点.z())
    }

    /// 単位の向きを与えた長さだけ伸ばした変位。
    pub fn 向きと長さから(向き: ビュー空間の向き, 長さ: メートル) -> Self {
        let 成分 = 向き.成分();
        Self {
            成分: [成分[0] * 長さ.値(), 成分[1] * 長さ.値(), 成分[2] * 長さ.値()],
        }
    }

    pub fn 成分(self) -> [f32; 3] {
        self.成分
    }

    pub fn 長さ(self) -> メートル {
        メートル::生成する(self.成分.iter().map(|値| 値 * 値).sum::<f32>().sqrt())
    }

    /// 与えた向きの成分だけを取り出した長さ。符号は向きと同じ側が正である。
    pub fn 向きへの射影(self, 向き: ビュー空間の向き) -> メートル {
        let 相手 = 向き.成分();
        メートル::生成する(self.成分[0] * 相手[0] + self.成分[1] * 相手[1] + self.成分[2] * 相手[2])
    }

    /// この変位が指す単位の向き。長さが0なら向きが定まらないため値なしを返す。
    pub fn 向きへ正規化する(self) -> Option<ビュー空間の向き> {
        let 長さ = self.長さ().値();
        if !長さ.is_finite() || 長さ <= 0.0 {
            return None;
        }
        ビュー空間の向き::生成する([self.成分[0] / 長さ, self.成分[1] / 長さ, self.成分[2] / 長さ]).ok()
    }

    /// 基点をこの変位だけ動かした先。
    pub fn 位置へ足す(self, 基点: 位置<ビュー>) -> 位置<ビュー> {
        位置::生成する(
            基点.x() + メートル::生成する(self.成分[0]),
            基点.y() + メートル::生成する(self.成分[1]),
            基点.z() + メートル::生成する(self.成分[2]),
        )
    }
}
