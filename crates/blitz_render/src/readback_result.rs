//! `一フレーム描画して読み戻す` の結果を表す判別共用体。
//!
//! 読み戻した画像の型で構成するのは、対象(提示画像・圧縮前のHDR)ごとに画素の表現が違い、呼び出したエントリが返る画像の型を決めるためである。要求と結果の対応を型で保てば、呼び出し元が「起こりえない対象の画像」を扱う枝を書かずに済む。
//!
//! 参照: `_doc/開発スレッド/開発スレッド_2026-07-20_M0実装.md`「判断9」。

use crate::draw_result::見送り理由;

/// ピクセル読み戻し付き描画が正常終了したときに返す結果。
/// `描画結果` と同様、最小化中・再構築中の非描画はエラーでなくこの型で表す。
#[derive(Debug, Clone)]
pub enum 読み戻し結果<画像> {
    /// フレームを完成させ、提示後にホスト可視バッファから読み戻した。
    読み戻した(画像),
    /// 提示可能な状態でなかったため、このフレームの描画・読み戻しを見送った。
    見送った(見送り理由),
}
