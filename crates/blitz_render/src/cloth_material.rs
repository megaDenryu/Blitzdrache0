//! 布シミュレーションのGPU境界型(判断52・54)。blitz_simが生成したバイト列・一覧を検証付きで
//! 保持する。バイト列のレイアウトはshaders/cloth_step.slang冒頭のバインディング表と一致する
//! (粒子32バイト・拘束の引数16バイト/拘束・ラグランジュ乗数4バイト/拘束)。色の区間の検証は`coloring`、拘束の内容の検証は
//! `constraint_check`、拒む入力は`error`、GPUから写した粒子と乗数の器は`readback`、刻み幅の型は`time_step_width`が持つ。

mod coloring;
mod constraint_check;
mod error;
mod readback;
#[cfg(test)]
mod tests;
mod time_step_width;

pub use coloring::{布の彩色の区間, 布の彩色の色数上限};
pub use error::布素材エラー;
pub use readback::布の読み戻し;
pub use time_step_width::布の刻み幅;

/// 布の距離拘束の1刻みの反復回数。GPUは色ごとのディスパッチをこの回数繰り返し、CPUの参照計算は同じ拘束の並びをこの回数回す。
pub const 布の拘束の反復回数: u32 = 4;

/// 粒子どうしの自己衝突(空間ハッシュと分離の工程)を積むかどうか。CPUの参照計算との突き合わせは、分離が原子加算の順序に依って
/// CPUで再現できないため`行わない`で走らせる。本番の布は`行う`である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 布の自己衝突 {
    行う,
    行わない,
}

/// 布の物性・空間定数と刻み幅。単位はシーンのワールド単位(Foxは1単位約1cm)で、値はアプリが与える。
/// 布の硬さはここに無く、拘束の引数バイト列が拘束ごとに持つコンプライアンスが正本である(Issue #36「物性」)。
/// 刻み幅は時間の規律の基本刻みをコンポジションルートが注入した値であり、レンダラーは既定値を持たない。
#[derive(Debug, Clone, Copy)]
pub struct 布定数 {
    pub 重力: [f32; 3],
    pub 粒子間隔: f32,
    pub グリッド原点: [f32; 3],
    pub 速度減衰: f32,
    pub 自己衝突: 布の自己衝突,
    pub 刻み幅: 布の刻み幅,
}

/// 布素材を組む材料。生成の口が受け取る値の束であり、検証はまだ済んでいない。
#[derive(Debug, Clone)]
pub struct 布素材の材料 {
    pub 粒子バイト列: Vec<u8>,
    pub 拘束の引数バイト列: Vec<u8>,             // 彩色で並べ替えた順の拘束(a添字・b添字・静止長・コンプライアンス)
    pub ラグランジュ乗数の初期バイト列: Vec<u8>, // 拘束ごと4バイト。刻みの開始でGPUが零へ戻す
    pub 色の区間一覧: Vec<布の彩色の区間>,
    pub インデックス一覧: Vec<u32>,
    pub アタッチ対応一覧: Vec<[u32; 2]>,
    pub 一辺粒子数: u32,
    pub 定数: 布定数,
}

/// 布1枚ぶんのGPU入力。生成が拘束の内容(端点の範囲・両端が別の粒子・同じ色で端点を共有しない・静止長とコンプライアンスの定義域)まで
/// 検証する。スキン頂点添字(アタッチ対応の第2要素)の検証は、スキン済み頂点数を知るレンダラー生成時に行う。
#[derive(Debug, Clone)]
pub struct 布素材 {
    pub(crate) 粒子バイト列: Vec<u8>,
    pub(crate) 拘束の引数バイト列: Vec<u8>,
    pub(crate) ラグランジュ乗数の初期バイト列: Vec<u8>,
    pub(crate) 色の区間一覧: Vec<布の彩色の区間>,
    pub(crate) インデックス一覧: Vec<u32>,
    pub(crate) アタッチ対応一覧: Vec<[u32; 2]>,
    pub(crate) 粒子数: u32,
    pub(crate) 拘束の数: u32,
    pub(crate) 一辺粒子数: u32,
    pub(crate) 定数: 布定数,
}

impl 布素材 {
    pub fn 生成する(材料: 布素材の材料) -> Result<Self, 布素材エラー> {
        if 材料.一辺粒子数 < 2 {
            return Err(布素材エラー::一辺粒子数不足(材料.一辺粒子数));
        }
        let 粒子数 = 材料.一辺粒子数 * 材料.一辺粒子数;
        let 粒子数usize = usize::try_from(粒子数).unwrap_or_else(|_| panic!("粒子数がusizeに収まらない"));
        長さを検証する("粒子バイト列", 材料.粒子バイト列.len(), 粒子数usize * 32)?;
        let 拘束の数 = coloring::拘束の数を読む(&材料.拘束の引数バイト列)?;
        長さを検証する(
            "ラグランジュ乗数の初期バイト列",
            材料.ラグランジュ乗数の初期バイト列.len(),
            拘束の数.配列の長さ() * 4,
        )?;
        coloring::色の区間を検証する(&材料.色の区間一覧, 拘束の数)?;
        constraint_check::拘束の内容を検証する(&材料.拘束の引数バイト列, 粒子数, &材料.色の区間一覧)?;
        for &添字 in &材料.インデックス一覧 {
            添字を検証する("インデックス一覧", 添字, 粒子数)?;
        }
        for 対応 in &材料.アタッチ対応一覧 {
            添字を検証する("アタッチ対応一覧", 対応[0], 粒子数)?;
        }
        Ok(Self {
            粒子バイト列: 材料.粒子バイト列,
            拘束の引数バイト列: 材料.拘束の引数バイト列,
            ラグランジュ乗数の初期バイト列: 材料.ラグランジュ乗数の初期バイト列,
            色の区間一覧: 材料.色の区間一覧,
            インデックス一覧: 材料.インデックス一覧,
            アタッチ対応一覧: 材料.アタッチ対応一覧,
            粒子数,
            拘束の数: 拘束の数.値(),
            一辺粒子数: 材料.一辺粒子数,
            定数: 材料.定数,
        })
    }
}

fn 長さを検証する(名前: &'static str, 実際: usize, 期待: usize) -> Result<(), 布素材エラー> {
    if 実際 != 期待 {
        return Err(布素材エラー::バイト列長不一致 { 名前, 期待, 実際 });
    }
    Ok(())
}

fn 添字を検証する(名前: &'static str, 添字: u32, 粒子数: u32) -> Result<(), 布素材エラー> {
    if 添字 >= 粒子数 {
        return Err(布素材エラー::布粒子添字範囲外 { 名前, 添字, 粒子数 });
    }
    Ok(())
}
