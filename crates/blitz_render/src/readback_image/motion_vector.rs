//! 読み戻した1フレームぶんの動きベクトル画像。画素1つにつき正規化装置座標の横と縦の2成分を保持する。
//!
//! 半精度のビット列でなく単精度へ開いた形で運ぶのは、半精度の意味づけ(非正規化数・無限大・非数)を知るのを
//! GPU境界の1箇所に閉じるためである。読み手がもう1つ復号を持つと、丸めの食い違いが検収の差に化ける
//! (HDR中間画像の読み戻しと同じ理由である)。

/// 読み戻した1フレームぶんの動きベクトル。幅・高さと、行優先で1画素2要素(横・縦の順)の列を保持する。
#[derive(Debug, Clone)]
pub struct 動きベクトル読み戻し画像 {
    幅: u32,
    高さ: u32,
    正規化装置座標の成分: Vec<f32>,
}

impl 動きベクトル読み戻し画像 {
    /// 前提: `正規化装置座標の成分` は `幅 * 高さ * 2` 要素の、行優先に並んだ横と縦の列であること。
    pub(crate) fn 生成する(幅: u32, 高さ: u32, 正規化装置座標の成分: Vec<f32>) -> Self {
        Self {
            幅,
            高さ,
            正規化装置座標の成分,
        }
    }

    pub fn 幅(&self) -> u32 {
        self.幅
    }

    pub fn 高さ(&self) -> u32 {
        self.高さ
    }

    /// 行優先に並んだ横と縦の列。添字`2 * i`が画素`i`の横、`2 * i + 1`が縦である。
    pub fn 正規化装置座標の成分列(&self) -> &[f32] {
        &self.正規化装置座標の成分
    }
}
