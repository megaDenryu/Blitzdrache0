//! 読み戻した1フレームぶんの最終深度画像。D32_SFLOATのビット列をそのままの単精度の並びで保持する。
//!
//! 半精度のHDRと違って復号を挟まないのは、深度の形式が最初から単精度だからである。深度プリパスの三条件の突き合わせは
//! この並びのバイト一致で行うため、値を1度も丸め直さずに運ぶ。

/// 読み戻した1フレームぶんの最終深度。幅・高さと、行優先で1画素1要素の単精度の列を保持する。
#[derive(Debug, Clone)]
pub struct 深度読み戻し画像 {
    幅: u32,
    高さ: u32,
    深度: Vec<f32>,
}

impl 深度読み戻し画像 {
    /// 前提: `深度` は `幅 * 高さ` 要素の、行優先に並んだ単精度の列であること。
    pub(crate) fn 生成する(幅: u32, 高さ: u32, 深度: Vec<f32>) -> Self {
        Self { 幅, 高さ, 深度 }
    }

    pub fn 幅(&self) -> u32 {
        self.幅
    }

    pub fn 高さ(&self) -> u32 {
        self.高さ
    }

    /// 行優先に並んだ単精度の深度の列。書き出し側はこの並びをそのまま外部形式へ写す。
    pub fn 深度列(&self) -> &[f32] {
        &self.深度
    }
}
