//! 読み戻した1フレームぶんの局所可視度画像。両側ぼかしが最後に書いた符号値を、画素1つにつき1バイトの並びで保持する。
//!
//! 4成分の並びのまま運ばないのは、GPU上の形式が4成分なのは記憶画像の必須対応形式の都合であり、
//! 意味を持つのが第1成分だけだからである。読み手が毎回4バイトの歩幅を知っていなければならない形にすると、
//! 歩幅の取り違えが「写しが正本と食い違った」という誤った読みになる。

/// 読み戻した1フレームぶんの局所可視度。幅・高さと、行優先で1画素1要素の符号値の列を保持する。
#[derive(Debug, Clone)]
pub struct 局所可視度読み戻し画像 {
    幅: u32,
    高さ: u32,
    符号値: Vec<u8>,
}

impl 局所可視度読み戻し画像 {
    /// 前提: `符号値` は `幅 * 高さ` 要素の、行優先に並んだ第1成分の列であること(4成分からの取り出しはGPU境界が済ませる)。
    pub(crate) fn 生成する(幅: u32, 高さ: u32, 符号値: Vec<u8>) -> Self {
        Self { 幅, 高さ, 符号値 }
    }

    pub fn 幅(&self) -> u32 {
        self.幅
    }

    pub fn 高さ(&self) -> u32 {
        self.高さ
    }

    /// 行優先に並んだ符号値の列。CPU正本の`符号値列`と同じ並びであり、突き合わせはこの2つを比べる。
    pub fn 符号値列(&self) -> &[u8] {
        &self.符号値
    }
}
