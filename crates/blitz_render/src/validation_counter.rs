//! validation層の観測を表す2つの値オブジェクト: 層を有効にできたかどうかと、検出したエラー・警告の件数。
//!
//! 2つを同じ場所に置くのは、どちらか片方だけでは何も言えないためである。層が無い機材の0件は
//! 「指摘が無かった」ではなく「観測できていない」であり、件数を報告する側は必ず状況も一緒に運ぶ義務を持つ。

use std::sync::Arc;
use std::sync::atomic::{AtomicU64, Ordering};

/// Vulkanのvalidation層とdebug utils拡張が機材にあり、有効化できたかどうか。
///
/// 有効化の成否を真偽値でなく列挙で表すのは、「層が無い」ことを無言で成功として通さないためである。
/// 呼び出し元はこの値を報告へ出す義務を持つ(参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「検証」)。
///
/// `有効`は層と拡張がそろっておりインスタンスで有効にした状態で、指摘は検証カウンタが数える。
/// `環境に無い`は層または拡張が機材に無いため有効にできなかった状態で、検査はvalidationの指摘を観測できない。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 検証層の状況 {
    有効,
    環境に無い,
}

impl 検証層の状況 {
    /// 報告の1語として出す名前。xtaskの検収がこの語で状況を読む。
    pub fn 呼び名(&self) -> &'static str {
        match self {
            Self::有効 => "有効",
            Self::環境に無い => "環境に無い",
        }
    }
}

/// debug utilsメッセンジャーのコールバックから加算される、エラー・警告の合計件数。
/// clone しても同じ実体（同一のAtomicU64）を指す。
///
/// 注意: 破棄後（レンダラーDrop後）に読むこと。破棄処理自体が発するvalidation
/// メッセージも件数に含めるため、読み取りの前にレンダラーの全Vulkanリソースが
/// 破棄済みである必要がある。
#[derive(Debug, Clone)]
pub struct 検証カウンタ {
    件数: Arc<AtomicU64>,
}

impl 検証カウンタ {
    /// ゼロで初期化したカウンタを生成する。
    pub(crate) fn 生成する() -> Self {
        Self {
            件数: Arc::new(AtomicU64::new(0)),
        }
    }

    /// debug utilsメッセンジャーのuser_dataに渡すため、内部Arcを複製して返す。
    /// 加算自体はコールバックが生ポインタ越しにAtomicU64へ直接行うため、
    /// この型自身は加算メソッドを持たない。
    /// 呼び出し側（デバッグメッセンジャー構造体）がこの複製を保持し続けることで、
    /// メッセンジャー破棄までポインタの指す先が生存することを保証する。
    pub(crate) fn 内部参照を複製する(&self) -> Arc<AtomicU64> {
        Arc::clone(&self.件数)
    }

    /// 現在までの合計件数を読む。
    pub fn 件数を読む(&self) -> u64 {
        self.件数.load(Ordering::SeqCst)
    }
}
