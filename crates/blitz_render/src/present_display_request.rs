//! 実表示時刻計測を使うかどうかの起動時要求。レンダラー生成時に決まり、後から変えられない。

/// 実表示時刻計測に必要な拡張を有効化するかどうかの要求。
///
/// 注意: `要求しない`のとき、VK_KHR_present_id と VK_KHR_present_wait を論理デバイスで有効化しない。
/// 計測しない実行の論理デバイス構成を、この計測を入れる前と同一に保つためである。拡張の有効化自体が
/// ドライバーの提示ペーシングへ影響するかどうかは確かめられていない(この機材のフレーム間隔は時間帯で
/// 大きく変動し、有効化の有無を分離できなかった)。影響が無いと確認できるまでは触らない側を既定にする。
/// 参照: `_doc/計測/OW2_2026-07-25.md`「計測条件の分離と、機材側の時間変動」。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 実表示計測要求 {
    要求しない,
    要求する,
}
