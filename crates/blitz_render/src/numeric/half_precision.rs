//! 半精度(16ビット浮動小数)と単精度の相互変換。受け取るのは片方の表現、返すのはもう片方である。
//!
//! 自前で書くのは、この変換のためだけに外部クレートを増やさないためである(依存の追加は採用審査と白リストの更新を要する)。
//! クレートの根へ置くのは、GPUから読み戻す側とGPUへ書き込む側と「GPUが保つ値をCPUで再現する側」の3つが
//! 同じ丸めを要るためである。丸めが1箇所でも違うと、CPU正本とGPUの一致検査が写しの誤りでない差で落ちる。
//!
//! 半精度の最小の正規化数に満たない大きさの丸めは`subnormal`が持つ。

#[cfg(test)]
mod conversion_tests;
mod subnormal;

/// 半精度の16ビットを単精度へ開く。非正規化数は仮数に2の-24乗を掛けた値であり、無限大とNaNは指数を埋めて表す。
/// 単精度は半精度の値域と精度を完全に含むため、この向きでは丸めが起きない。
pub(crate) fn 半精度を単精度へ(ビット: u16) -> f32 {
    let 符号 = u32::from(ビット >> 15) << 31;
    let 指数 = u32::from((ビット >> 10) & 0x1f);
    let 仮数 = u32::from(ビット & 0x03ff);
    if 指数 == 0 {
        let 大きさ = f32::from(ビット & 0x03ff) * 非正規化数の刻み();
        return if 符号 == 0 { 大きさ } else { -大きさ };
    }
    if 指数 == 0x1f {
        return f32::from_bits(符号 | 0x7f80_0000 | (仮数 << 13));
    }
    // 半精度の指数の下駄は15、単精度は127であるため、差の112を足す。
    f32::from_bits(符号 | ((指数 + 112) << 23) | (仮数 << 13))
}

/// 単精度を半精度へ丸める。丸めは最近接であり、半精度で表せない小さすぎる値は0へ、大きすぎる値は無限大へ落ちる。
/// 非数は指数を埋めた仮数非零の形で保つ。
pub(crate) fn 単精度を半精度へ(値: f32) -> u16 {
    let ビット = 値.to_bits();
    let 符号 = (ビット >> 16) & 0x8000;
    let 単精度指数 = i32::try_from((ビット >> 23) & 0xff).unwrap_or_else(|_| panic!("単精度の指数が値域を外れた"));
    let 仮数 = ビット & 0x007f_ffff;
    if 単精度指数 == 0xff {
        let 非数の仮数 = if 仮数 == 0 { 0 } else { 0x0200 };
        return 十六ビットへ狭める(符号 | 0x7c00 | 非数の仮数);
    }
    // 半精度の最小の正規化数は2の-14乗である。それ未満はすべて非正規化数の枠へ落ちるため、
    // 正規化数の丸めより先に判定する。丸めの後に判定すると、2の-14乗へ切り上がる値まで0にしてしまう。
    let 丸める前の指数 = 単精度指数 - 127 + 15;
    if 丸める前の指数 <= 0 {
        return subnormal::非正規化数へ丸める(符号, 仮数, 丸める前の指数);
    }
    // 最近接への丸めは、切り捨てる13ビットの半分を足してから落とす。奇数側へ寄るのを避けるため、
    // 残す最下位ビットが1のときだけ1を足す(偶数への丸め)。
    let 丸めた = 仮数 + 0x0fff + ((仮数 >> 13) & 1);
    let 桁上がり = i32::try_from(丸めた >> 23).unwrap_or_else(|_| panic!("仮数の桁上がりがi32に収まらない"));
    let 半精度指数 = 丸める前の指数 + 桁上がり;
    if 半精度指数 >= 0x1f {
        return 十六ビットへ狭める(符号 | 0x7c00);
    }
    let 半精度指数 = u32::try_from(半精度指数).unwrap_or_else(|_| panic!("半精度の指数が負になった"));
    十六ビットへ狭める(符号 | (半精度指数 << 10) | ((丸めた & 0x007f_ffff) >> 13))
}

/// 倍精度の値を、GPUの半精度の画像が保つ値へ丸める。CPUの正本がGPUと同じ入力を見るために使う。
pub(crate) fn 倍精度を半精度へ丸める(値: f64) -> f64 {
    f64::from(半精度を単精度へ(単精度を半精度へ(glam::DVec3::splat(値).as_vec3().x)))
}

fn 十六ビットへ狭める(値: u32) -> u16 {
    u16::try_from(値 & 0xffff).unwrap_or_else(|_| panic!("16ビットへの切り出しに失敗した"))
}

fn 非正規化数の刻み() -> f32 {
    f32::from_bits(0x3380_0000)
}
