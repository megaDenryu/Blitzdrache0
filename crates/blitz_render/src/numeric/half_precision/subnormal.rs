//! 半精度の最小の正規化数に満たない大きさを、半精度の非正規化数へ丸める工程。受け取るのは符号と単精度の仮数と
//! 丸める前の半精度の指数、返すのは符号を含む半精度のビット列である。
//!
//! 非正規化数を捨てて0にしないのは、半精度が2の-24乗まで表せるためである。2の-14乗未満をすべて0にすると、
//! 遠方環境の暗い側の放射輝度が消える。しかもGPUへ書く値とCPUの期待値が同じ変換を通るため、
//! 消えたことが検収の一致に現れない。値域の広い量を扱う変換は、表せる範囲の端まで表さなければならない。
//!
//! 非正規化数は仮数を2の-24乗の整数倍として表す。単精度の暗黙の1を立てた24ビットの有効数字を、
//! 指数の差だけ右へずらすとその整数になる。ずらして落ちるビットは最近接偶数丸めで拾う。

/// 半精度の非正規化数の刻み(2の-24乗)を1とする整数へ、有効数字をずらす基準。丸める前の半精度の指数が0のとき、
/// 24ビットの有効数字をこの幅だけ右へずらすと非正規化数の仮数になる。
const 指数0でのずらし幅: i32 = 14;

/// これより大きくずらす値は、最近接偶数丸めでも必ず0になる。2の-26乗未満が該当する。
/// 上限を置くのは、u32のずらし幅が32以上になる操作を起こさないためでもある。
const ずらし幅の上限: i32 = 25;

pub(super) fn 非正規化数へ丸める(符号: u32, 仮数: u32, 丸める前の指数: i32) -> u16 {
    let ずらし幅 = 指数0でのずらし幅 - 丸める前の指数;
    if ずらし幅 > ずらし幅の上限 {
        return 十六ビットへ狭める(符号);
    }
    let ずらし幅 = u32::try_from(ずらし幅).unwrap_or_else(|_| panic!("非正規化数のずらし幅が負になった: {ずらし幅}"));
    let 有効数字 = 0x0080_0000 | 仮数;
    let 落とす分 = 1u32 << ずらし幅;
    let 丸めの境目 = 落とす分 >> 1;
    let 端数 = 有効数字 & (落とす分 - 1);
    let 非正規化仮数 = 有効数字 >> ずらし幅;
    // 端数がちょうど半分のときは偶数側へ寄せる。切り上げた結果が1024になる場合は、そのビット列が
    // 最小の正規化数(指数1・仮数0)そのものであるため、追加の場合分けを持たずに正しい値になる。
    let 切り上げる = 端数 > 丸めの境目 || (端数 == 丸めの境目 && (非正規化仮数 & 1) == 1);
    十六ビットへ狭める(符号 | (非正規化仮数 + u32::from(切り上げる)))
}

fn 十六ビットへ狭める(値: u32) -> u16 {
    u16::try_from(値 & 0xffff).unwrap_or_else(|_| panic!("16ビットへの切り出しに失敗した"))
}
