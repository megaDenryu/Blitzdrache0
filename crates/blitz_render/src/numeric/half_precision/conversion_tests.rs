//! 半精度と単精度の相互変換の検査。担うのは、正確に表せる値の往復・正規化数の丸め幅・非正規化数の全域・
//! 値域の外の落ち方・非数の保持の5つである。
//!
//! 非正規化数を個別のビット列まで固定するのは、この域を0へ落とす実装がGPUへ書く値とCPUの期待値の
//! 両方を同じだけ壊し、読み戻しの一致検査では捉えられないためである。

#![allow(clippy::unwrap_used)]

use super::{半精度を単精度へ, 単精度を半精度へ};

/// 半精度の非正規化数の刻み(2の-24乗)。
const 非正規化数の刻み: f32 = 5.960_464_5e-8;

#[test]
fn 半精度で正確に表せる値は往復で変わらない() {
    for 値 in [0.0_f32, 0.5, 1.0, 2.0, 0.25, 1024.0, -3.5] {
        assert_eq!(半精度を単精度へ(単精度を半精度へ(値)), 値);
    }
}

#[test]
fn 往復の相対誤差は半精度の刻みに収まる() {
    for 添字 in 1..2000_u16 {
        let 値 = f32::from(添字) * 0.0137;
        let 往復 = 半精度を単精度へ(単精度を半精度へ(値));
        assert!((往復 - 値).abs() / 値 < 5.0e-4, "{値}が{往復}へ丸められた");
    }
}

#[test]
fn 非正規化数の代表がビット列まで一致する() {
    // 2の-15乗は最小の正規化数の半分であり、非正規化仮数512で表す。
    assert_eq!(単精度を半精度へ(3.051_757_8e-5), 0x0200);
    // 2の-24乗は表せる最小の非零であり、非正規化仮数1で表す。
    assert_eq!(単精度を半精度へ(非正規化数の刻み), 0x0001);
    // 2の-14乗は最小の正規化数であり、指数1・仮数0で表す。
    assert_eq!(単精度を半精度へ(6.103_515_6e-5), 0x0400);
}

#[test]
fn 非正規化数の全域が往復で刻みの整数倍を保つ() {
    for 仮数 in 1..1024_u16 {
        let ビット列 = 仮数;
        let 値 = 半精度を単精度へ(ビット列);
        assert_eq!(値, f32::from(仮数) * 非正規化数の刻み);
        assert_eq!(単精度を半精度へ(値), ビット列, "非正規化仮数{仮数}が往復で変わった");
    }
}

#[test]
fn 非正規化数の下端は最近接偶数で丸める() {
    // 刻みのちょうど半分は偶数側の0へ落ちる。
    assert_eq!(単精度を半精度へ(非正規化数の刻み * 0.5), 0x0000);
    // 半分より大きければ1へ切り上がる。
    assert_eq!(単精度を半精度へ(非正規化数の刻み * 0.75), 0x0001);
    // 刻みの1.5倍はちょうど半分であり、偶数側の2へ寄る。
    assert_eq!(単精度を半精度へ(非正規化数の刻み * 1.5), 0x0002);
    // 刻みの2.5倍もちょうど半分であり、偶数側の2へ寄る。
    assert_eq!(単精度を半精度へ(非正規化数の刻み * 2.5), 0x0002);
}

#[test]
fn 最小の正規化数の直下は正規化数へ切り上がる() {
    // 非正規化仮数1023.5に当たる値は1024へ切り上がり、そのビット列は最小の正規化数である。
    assert_eq!(単精度を半精度へ(非正規化数の刻み * 1023.75), 0x0400);
}

#[test]
fn 値域の外は無限大と0へ落ちる() {
    assert!(半精度を単精度へ(単精度を半精度へ(1.0e30)).is_infinite());
    assert_eq!(半精度を単精度へ(単精度を半精度へ(1.0e-12)), 0.0);
    assert_eq!(単精度を半精度へ(-1.0e-12), 0x8000);
}

#[test]
fn 非数は非数のまま保たれる() {
    assert!(半精度を単精度へ(単精度を半精度へ(f32::NAN)).is_nan());
}
