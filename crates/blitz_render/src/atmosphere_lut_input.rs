//! 大気LUTの1フレーム入力。焼く大気と観測の条件、そのフレームで何を焼き直すかの指示を1つに束ねる。
//!
//! 焼き直すかどうかを上位層が決めるのは、判定に使う鍵が方針の全パラメータを並べた完全比較キーであり、
//! それを持つのが方針を保持する層だからである。可変なdirty通知でなく値の比較で決めるため、
//! 通知の付け忘れという欠陥の種類そのものが生じない。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「更新の決定性」

use crate::atmosphere::{スカイビュー観測条件, 大気散乱媒体, 空中遠近観測条件};

/// そのフレームで大気LUTのどれを焼き直すか。腕は依存の階層をそのまま表し、上の腕が下の腕を含む。
///
/// 透過率と多重散乱だけを焼く腕を持たないのは、スカイビューと空中遠近の内容が2枚の両方に依存し、
/// 大気が変わった以上どちらも必ず焼き直さねばならないためである。
/// スカイビューを単独で焼く腕を持たないのは、空中遠近も太陽の向きを読むため、太陽が動いた以上両方が変わるためである。
/// 逆に空中遠近だけを焼く腕が要るのは、大気も太陽も観測点も動かずカメラだけが動いたフレームがあり、
/// 空中遠近だけがカメラに依存するためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 大気LUT生成指示 {
    /// どのLUTも前フレームと同じ条件である。生成パスを1本も積まない。
    前の結果を使う,
    /// 大気も太陽も観測点も前フレームと同じで、カメラの姿勢か射影か距離範囲が動いた。空中遠近だけを焼き直す。
    空中遠近だけ焼き直す,
    /// 大気は前フレームと同じで、太陽の向きか観測点が動いた。スカイビューと空中遠近を焼き直す。
    スカイビューと空中遠近を焼き直す,
    /// 大気が前フレームから変わった、またはまだ1度も焼いていない。4枚すべてを焼き直す。
    全部焼き直す,
}

/// 空を持つ世界のフレームが毎フレーム渡す大気の入力。
#[derive(Debug, Clone, Copy)]
pub struct 大気LUT入力 {
    媒体: 大気散乱媒体,
    スカイビュー条件: スカイビュー観測条件,
    空中遠近条件: 空中遠近観測条件,
    生成指示: 大気LUT生成指示,
}

impl 大気LUT入力 {
    pub fn 生成する(
        媒体: 大気散乱媒体,
        スカイビュー条件: スカイビュー観測条件,
        空中遠近条件: 空中遠近観測条件,
        生成指示: 大気LUT生成指示,
    ) -> Self {
        Self {
            媒体,
            スカイビュー条件,
            空中遠近条件,
            生成指示,
        }
    }

    pub(crate) fn 媒体(&self) -> &大気散乱媒体 {
        &self.媒体
    }

    pub(crate) fn スカイビュー条件(&self) -> スカイビュー観測条件 {
        self.スカイビュー条件
    }

    pub(crate) fn 空中遠近条件(&self) -> 空中遠近観測条件 {
        self.空中遠近条件
    }

    pub(crate) fn 生成指示(&self) -> 大気LUT生成指示 {
        self.生成指示
    }
}
