//! 大気LUTの1フレーム入力。焼く大気と観測の条件、そのフレームで何を焼き直すかの指示を1つに束ねる。
//!
//! 焼き直すかどうかを上位層が決めるのは、判定に使う鍵が方針の全パラメータを並べた完全比較キーであり、
//! それを持つのが方針を保持する層だからである。可変なdirty通知でなく値の比較で決めるため、
//! 通知の付け忘れという欠陥の種類そのものが生じない。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「更新の決定性」

use crate::atmosphere::{スカイビュー観測条件, 大気散乱媒体};

/// そのフレームで大気LUTのどれを焼き直すか。
///
/// 透過率と多重散乱だけを焼く腕を持たないのは、スカイビューの内容が2枚の両方に依存し、大気が変わった以上
/// スカイビューも必ず焼き直さねばならないためである。逆にスカイビューだけを焼く腕が要るのは、
/// 大気が変わらないまま太陽や観測点が動くフレームがあるためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 大気LUT生成指示 {
    /// どのLUTも前フレームと同じ条件である。生成パスを1本も積まない。
    前の結果を使う,
    /// 大気は前フレームと同じで、太陽の向きか観測点が動いた。スカイビューだけを焼き直す。
    スカイビューだけ焼き直す,
    /// 大気が前フレームから変わった、またはまだ1度も焼いていない。3枚すべてを焼き直す。
    全部焼き直す,
}

/// 空を持つ世界のフレームが毎フレーム渡す大気の入力。
#[derive(Debug, Clone, Copy)]
pub struct 大気LUT入力 {
    媒体: 大気散乱媒体,
    観測条件: スカイビュー観測条件,
    生成指示: 大気LUT生成指示,
}

impl 大気LUT入力 {
    pub fn 生成する(媒体: 大気散乱媒体, 観測条件: スカイビュー観測条件, 生成指示: 大気LUT生成指示) -> Self {
        Self {
            媒体, 観測条件, 生成指示
        }
    }

    pub(crate) fn 媒体(&self) -> &大気散乱媒体 {
        &self.媒体
    }

    pub(crate) fn 観測条件(&self) -> スカイビュー観測条件 {
        self.観測条件
    }

    pub(crate) fn 生成指示(&self) -> 大気LUT生成指示 {
        self.生成指示
    }

    /// そのフレームでLUTを1枚でも焼くか。焼くフレームは媒体のユニフォームを書き直す。
    pub(crate) fn 何かを焼くか(&self) -> bool {
        !matches!(self.生成指示, 大気LUT生成指示::前の結果を使う)
    }
}
