//! 粒子系GPUパスへ渡す初期状態。1要素32バイトの契約を公開境界で検証する。

use thiserror::Error;

const 要素バイト数: usize = 32;

#[derive(Debug, Error)]
pub enum 粒子素材エラー {
    #[error("粒子素材の要素数が0だった")]
    要素なし,
    #[error("粒子素材の要素数{0}がコンピュート計算の班幅64の倍数ではなかった")]
    計算の班幅不一致(u32),
    #[error("粒子素材の更新数{更新}または描画数{描画}がバッファ要素数{バッファ}を超えた")]
    要素範囲外 { バッファ: u32, 更新: u32, 描画: u32 },
    #[error("粒子素材のバイト長{実際}が要素数{要素数}に必要な長さ{期待}と一致しない")]
    バイト長不一致 { 要素数: u32, 期待: usize, 実際: usize },
}

#[derive(Debug, Clone)]
pub struct 粒子素材 {
    pub(crate) 初期バイト列: Vec<u8>,
    pub(crate) 更新スレッド数: u32,
    pub(crate) 描画要素数: u32,
}

impl 粒子素材 {
    pub fn 生成する(初期バイト列: Vec<u8>, 要素数: u32) -> Result<Self, 粒子素材エラー> {
        Self::個別件数で生成する(初期バイト列, 要素数, 要素数, 要素数)
    }

    pub fn 個別件数で生成する(
        初期バイト列: Vec<u8>,
        バッファ要素数: u32,
        更新スレッド数: u32,
        描画要素数: u32,
    ) -> Result<Self, 粒子素材エラー> {
        if バッファ要素数 == 0 || 更新スレッド数 == 0 || 描画要素数 == 0 {
            return Err(粒子素材エラー::要素なし);
        }
        if !更新スレッド数.is_multiple_of(64) {
            return Err(粒子素材エラー::計算の班幅不一致(更新スレッド数));
        }
        if 更新スレッド数 > バッファ要素数 || 描画要素数 > バッファ要素数 {
            return Err(粒子素材エラー::要素範囲外 {
                バッファ: バッファ要素数,
                更新: 更新スレッド数,
                描画: 描画要素数,
            });
        }
        let 要素数usize =
            usize::try_from(バッファ要素数).unwrap_or_else(|_| panic!("u32がusizeへ変換できないプラットフォームは対象外: {バッファ要素数}"));
        let 期待 = 要素数usize * 要素バイト数;
        if 初期バイト列.len() != 期待 {
            return Err(粒子素材エラー::バイト長不一致 {
                要素数: バッファ要素数,
                期待,
                実際: 初期バイト列.len(),
            });
        }
        Ok(Self {
            初期バイト列,
            更新スレッド数,
            描画要素数,
        })
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn 要素数とバイト長が一致する素材だけを受理する() {
        assert!(粒子素材::生成する(vec![0; 2048], 64).is_ok());
        assert!(matches!(粒子素材::生成する(vec![0; 32], 64), Err(粒子素材エラー::バイト長不一致 { .. })));
        assert!(matches!(粒子素材::生成する(vec![0; 32], 1), Err(粒子素材エラー::計算の班幅不一致(1))));
        assert!(matches!(粒子素材::生成する(Vec::new(), 0), Err(粒子素材エラー::要素なし)));
        assert!(粒子素材::個別件数で生成する(vec![0; 4096], 128, 64, 64).is_ok());
    }
}
