//! そのフレームの3本のビュー射影と、どの用途がどれを読むかの規約。担当するのは、ずらし無し・ずらし付き・
//! 前フレームの3つを1つの組として保ち、用途の名前でだけ取り出させることである。
//!
//! 3本を別々の引数で運ばないのは、どれも同じ`変換<ワールド, クリップ>`であり、並びを取り違えても型検査に
//! 掛からないためである。組にすると取り違えは名前の間違いとして読み手に見える。
//! 参照: `_doc/設計/時間再構成.md`「判断a」「判断b」

use blitz_math::{クリップ, ワールド, 変換};

#[derive(Debug, Clone, Copy)]
pub struct ビュー射影の組 {
    ずらし無し: 変換<ワールド, クリップ>,
    ずらし付き: 変換<ワールド, クリップ>,
    前フレーム: 変換<ワールド, クリップ>,
}

impl ビュー射影の組 {
    pub fn 生成する(
        ずらし無し: 変換<ワールド, クリップ>, ずらし付き: 変換<ワールド, クリップ>, 前フレーム: 変換<ワールド, クリップ>
    ) -> Self {
        Self {
            ずらし無し,
            ずらし付き,
            前フレーム,
        }
    }

    /// 可視判定と多段シャドウの当てはめが読む。1画素未満の揺れで視錐台の境界の対象が出入りしたり、
    /// テクセルスナップの基準が動いて静止物の影が泳いだりすることを避けるためである。
    pub fn ずらし無し(&self) -> 変換<ワールド, クリップ> {
        self.ずらし無し
    }

    /// 深度プリパス・シーン描画・空の3つが読む。空はこの射影の逆から視線を復元する。
    pub fn ずらし付き(&self) -> 変換<ワールド, クリップ> {
        self.ずらし付き
    }

    /// 今フレームのカメラ大域原点で表し直した、前フレームのずらし無しビュー射影。動きベクトルの材料になる。
    pub fn 前フレーム(&self) -> 変換<ワールド, クリップ> {
        self.前フレーム
    }
}
