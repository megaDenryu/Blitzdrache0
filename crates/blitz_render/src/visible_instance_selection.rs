//! そのフレームに描く個体の並びと、その並びをLOD段ごとの範囲へ切り分けた区間。可視判定と段選択はエンジン側の
//! 純ロジックが行い、レンダラーは結果だけを受け取る。選択を持たない描画対象は全個体を最詳細段で描く。
//!
//! 1本の可視ID列は群の全個体を段ごとの連続範囲へ並べ、各段の範囲の内側を
//! `[シーンのみ可視][両方可視][シャドウのみ可視][どちらも不可視]`の順に並べる。
//! この並びによって、交差する2つの可視集合がどちらも1本の列の中の連続範囲になり、パスごとに列を分けずに済む。
//! **不変条件: シャドウパスの可視集合はカメラ視錐台で絞った可視集合の流用であってはならない。** 画面外の個体が
//! 画面内へ影を落としうるためである。この不変条件は、列が常に全個体の並べ替えであること(長さ・値域・重複の3検査)と、
//! 段の範囲が列を隙間なく埋めて2つのパス範囲が4区分の並びに従うこと(`partition_check`)で守る
//! (参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」)。
//! 選択1件の形は`selection`、選択の一覧と検査は`list`、段の範囲は`stage_range`、パスごとの範囲は`pass_range`、
//! 列を読むパスの数え方は`visible_pass`にある。

