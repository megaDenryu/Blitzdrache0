//! そのフレームに描く個体の並びと、その並びをパス別・LOD段別の区間へ切り分けた配置。可視判定と段選択はエンジン側の
//! 純ロジックが行い、レンダラーは結果だけを受け取る。選択を持たない描画対象は全個体を最詳細段で描く。
//!
//! 1本の可視ID列はパスの正典順(シーン→距離区分0から距離区分3)に区間を並べ、各パスの区間の内側を段番号の順に並べる。
//! 同じ個体IDが複数の距離区分の区間へ現れることを許すため、列は全個体の並べ替えではなくなり、長さはフレームごとに変わる。
//! **不変条件: シャドウ側の可視集合はカメラ視錐台で絞った可視集合の流用であってはならない。** 画面外の個体が
//! 画面内へ影を落としうるためである。距離区分別のカリングでは、各距離区分のライトビュー射影から導いた視錐台がこの判定を行う。
//! 列の作りの担保は3つに分かれる。パスごとの区間が列を正典順に隙間なく埋めること(`interval_layout`)、
//! 段別個体数の合計が描画対象の個体数と一致すること、1つのパスの区間の中で同じ個体IDが重複しないこと
//! (後の2つは書き込み境界の`render_object_resources`が見る)。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」
//!
//! 選択1件の形は`selection`、選択の一覧と検査は`list`、段の区間は`stage_range`、パスごとの区間は`pass_range`、
//! 列を読むパスとその順序は`visible_pass`にある。

