//! 詳細段メッシュ列: 描画対象1つ分の幾何を、詳細段の昇順に並べた非空のメッシュ列として持つ。
//! 段を1つしか持たない対象も同じ型で表す。レンダラーの仕事はどちらでも「選ばれた段を描く」の1つだけであり、段の有無で描画の手順が変わらないためである。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「LOD」

use crate::mesh_material::メッシュ素材;

pub struct 詳細段メッシュ列 {
    段一覧: Vec<メッシュ素材>,
}

impl 詳細段メッシュ列 {
    pub fn 生成する(最詳細段: メッシュ素材, より粗い段一覧: Vec<メッシュ素材>) -> Self {
        let mut 段一覧 = Vec::with_capacity(1 + より粗い段一覧.len());
        段一覧.push(最詳細段);
        段一覧.extend(より粗い段一覧);
        Self { 段一覧 }
    }

    pub(crate) fn 段一覧(&self) -> &[メッシュ素材] {
        &self.段一覧
    }

    pub fn 最詳細段(&self) -> &メッシュ素材 {
        match self.段一覧.first() {
            Some(メッシュ) => メッシュ,
            None => panic!("詳細段メッシュ列は1段以上を持つ不変条件に違反した"),
        }
    }
}
