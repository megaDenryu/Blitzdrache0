//! 高度から規格化密度への対応を、下から順に重ねた2つの層で表したもの。

use blitz_math::{メートル, 逆メートル};

use super::{大気数学エラー, 密度分布層};

/// 高度が第1層の幅より小さければ第1層、そうでなければ第2層の式で密度を決める分布。
/// 層を2つに固定するのは、大気の各成分がとる形が「指数分布」と「高度に対して折れ線のテント関数」の2つに尽きるためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 密度分布 {
    層: [密度分布層; 2],
}

impl 密度分布 {
    pub fn 生成する(第1層: 密度分布層, 第2層: 密度分布層) -> Self {
        Self { 層: [第1層, 第2層] }
    }

    /// 地表で1、上へ向かって尺度高度ごとに1/eへ減る指数分布。
    /// 第1層の幅を0にすることで、全高度が第2層の式で決まる。
    pub fn 指数分布(尺度高度: メートル) -> Result<Self, 大気数学エラー> {
        if !尺度高度.値().is_finite() || 尺度高度.値() <= 0.0 {
            return Err(大気数学エラー::値域外("尺度高度", 尺度高度.値()));
        }
        let 零 = 逆メートル::生成する(0.0);
        let 減衰 = 逆メートル::生成する(-逆メートル::長さの逆数(尺度高度).値());
        let 空 = 密度分布層::生成する(メートル::生成する(0.0), 0.0, 零, 零, 0.0)?;
        let 本体 = 密度分布層::生成する(メートル::生成する(0.0), 1.0, 減衰, 零, 0.0)?;
        Ok(Self::生成する(空, 本体))
    }

    /// 下端高度で0、頂点高度で1、上端高度で再び0になる折れ線。
    /// 区間の外は層の式が負の値を返し、規格化密度の切り詰めで0になる。
    pub fn テント(下端高度: メートル, 頂点高度: メートル, 上端高度: メートル) -> Result<Self, 大気数学エラー> {
        for (項目, 高度) in [("下端高度", 下端高度), ("頂点高度", 頂点高度), ("上端高度", 上端高度)] {
            if !高度.値().is_finite() || 高度.値() < 0.0 {
                return Err(大気数学エラー::値域外(項目, 高度.値()));
            }
        }
        if 下端高度 >= 頂点高度 || 頂点高度 >= 上端高度 {
            return Err(大気数学エラー::値域外("頂点高度", 頂点高度.値()));
        }
        let 上り幅 = (頂点高度 - 下端高度).値();
        let 下り幅 = (上端高度 - 頂点高度).値();
        let 零 = 逆メートル::生成する(0.0);
        let 上り = 密度分布層::生成する(頂点高度, 0.0, 零, 逆メートル::生成する(1.0 / 上り幅), -下端高度.値() / 上り幅)?;
        let 下り = 密度分布層::生成する(
            メートル::生成する(0.0),
            0.0,
            零,
            逆メートル::生成する(-1.0 / 下り幅),
            上端高度.値() / 下り幅,
        )?;
        Ok(Self::生成する(上り, 下り))
    }

    pub fn 層(&self) -> [密度分布層; 2] {
        self.層
    }
}
