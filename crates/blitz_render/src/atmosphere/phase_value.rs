//! 位相関数が返す、単位立体角あたりに振り分けられる光の割合。

use super::大気数学エラー;

/// 単位は毎ステラジアンである。全立体角にわたる積分が1になるよう正規化されているため、
/// 「散乱した光のうちこの向きへ進む割合の密度」という意味を持つ。
/// 不変条件: 有限かつ0以上である。負の割合は物理的に意味を持たない。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 位相関数値(f32);

impl 位相関数値 {
    pub fn 生成する(値: f32) -> Result<Self, 大気数学エラー> {
        if !値.is_finite() || 値 < 0.0 {
            return Err(大気数学エラー::値域外("位相関数値", 値));
        }
        Ok(Self(値))
    }

    /// 前提: 値は有限かつ0以上である。位相関数の評価だけがこの入口を使う。
    pub(super) fn 検証済みの値から(値: f32) -> Self {
        Self(値)
    }

    /// 毎ステラジアンの生値。境界(GPU・検証)専用と明示する。
    pub fn 毎ステラジアン(&self) -> f32 {
        self.0
    }
}
