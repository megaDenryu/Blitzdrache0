//! ある位置における散乱係数と消散係数の組。受け取るのは媒体と惑星中心を原点とする位置、返すのはその点の3成分ずつの係数である。
//!
//! 散乱と消散を同時に求めるのは、どちらも同じ規格化密度から導かれ、密度の評価を2度行う理由が無いためである。
//! 吸収層は光を散らさないため散乱係数へ寄与せず、消散係数にだけ現れる。

use super::density::規格化密度の生値;
use super::vector3::長さ;
use super::大気散乱媒体;

pub(super) struct 媒体標本 {
    pub(super) 散乱係数: [f64; 3],
    pub(super) 消散係数: [f64; 3],
}

impl 媒体標本 {
    pub(super) fn 求める(媒体: &大気散乱媒体, 位置: [f64; 3]) -> Self {
        let 消散 = 媒体.消散();
        let 高度 = 長さ(位置) - f64::from(消散.下端半径().値());
        let [レイリー, ミー, 吸収] = 消散.成分一覧();
        let レイリー密度 = 規格化密度の生値(&レイリー.密度分布(), 高度);
        let ミー密度 = 規格化密度の生値(&ミー.密度分布(), 高度);
        let 吸収密度 = 規格化密度の生値(&吸収.密度分布(), 高度);
        let レイリー散乱 = 係数の生値(媒体.レイリー散乱係数());
        let ミー散乱 = 係数の生値(媒体.ミー散乱係数());
        let レイリー消散 = 係数の生値(レイリー.消散係数());
        let ミー消散 = 係数の生値(ミー.消散係数());
        let 吸収消散 = 係数の生値(吸収.消散係数());
        let mut 標本 = Self {
            散乱係数: [0.0; 3],
            消散係数: [0.0; 3],
        };
        for 添字 in 0..3 {
            標本.散乱係数[添字] = レイリー散乱[添字] * レイリー密度 + ミー散乱[添字] * ミー密度;
            標本.消散係数[添字] = レイリー消散[添字] * レイリー密度 + ミー消散[添字] * ミー密度 + 吸収消散[添字] * 吸収密度;
        }
        標本
    }
}

fn 係数の生値(係数: super::消散係数RGB) -> [f64; 3] {
    係数.成分().map(|値| f64::from(値.値()))
}
