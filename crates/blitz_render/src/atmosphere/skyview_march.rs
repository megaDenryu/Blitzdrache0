//! 1本の視線について経路を刻み、太陽から来て観測点へ届く放射輝度を積む工程。
//! 受け取るのは媒体・2つの表・観測位置と視線と太陽の向き、返すのは太陽の放射照度を1としたときの放射輝度である。
//!
//! 多重散乱の積分(`multiscatter_march`)と違い、一次散乱に位相関数を掛ける。見る向きによって空の色が変わるのは
//! この位相の形が担っており、等方で置くと太陽周辺の明るさと地平線の色が失われる。1区間ぶんの積み方は
//! `skyview_step`が持ち、ここは経路の刻みと終わりの決め方だけを持つ。
//!
//! 注意: この積分は`shaders/atmosphere_skyview_march.slang`の写しを持つ。ここが正本であり、
//! 一致はGPU読み戻し検査が代表テクセルで確かめる。

use super::intersect::最近の球交差距離;
use super::multiscatter_march::経路長を決める;
use super::multiscatter_step::地面の照り返しを足す;
use super::multiscatter_table::多重散乱表;
use super::narrowing;
use super::skyview_step::{区間を積む, 視線の幾何};
use super::transmittance_table::透過率表;
use super::vector3::{内積, 進む};
use super::{ミー位相関数, レイリー位相関数, 大気散乱媒体, 大気数学エラー, 散乱角余弦};

/// 視線の経路を刻む区間の数。Hillaire 2020実装のスカイビューLUTと同じ30区間を採る。
/// 注意: この値は`shaders/atmosphere_skyview_march.slang`の`skyViewStepCount`と一致していなければならない。
/// 区間数が食い違うと同じ式でも離散化の誤差だけがずれ、読み戻し検査の代表テクセルが落ちる。
/// 一致は`cargo xtask conform`の定数一致検査が機械的に見る。
pub(super) const 標本区間数: u32 = 30;
/// 区間の中で媒体を評価する位置を、区間の始まりから区間長の何倍だけ進んだ所に置くか。
/// 注意: これは標本位置であって積分幅ではない。消散へ掛ける積分幅は全区間で区間長に等しい。
const 区間内の標本位置: f64 = 0.3;

pub(super) fn 視線を積分する(
    媒体: &大気散乱媒体,
    透過率表: &透過率表,
    多重散乱表: &多重散乱表,
    幾何: &視線の幾何,
) -> Result<[f64; 3], 大気数学エラー> {
    let 下端 = f64::from(媒体.消散().下端半径().値());
    let 上端 = f64::from(媒体.消散().上端半径().値());
    let 地表まで = 最近の球交差距離(幾何.観測位置, 幾何.視線, 下端);
    let 経路長 = 経路長を決める(地表まで, 最近の球交差距離(幾何.観測位置, 幾何.視線, 上端));
    let mut 放射輝度 = [0.0_f64; 3];
    if 経路長 <= 0.0 {
        return Ok(放射輝度);
    }
    let 位相 = 位相の組を求める(媒体, 幾何)?;
    let 区間長 = 経路長 / f64::from(標本区間数);
    let mut 通過率 = [1.0_f64; 3];
    for 区間 in 0..標本区間数 {
        let 標本距離 = (f64::from(区間) + 区間内の標本位置) * 区間長;
        let 位置 = 進む(幾何.観測位置, 幾何.視線, 標本距離);
        区間を積む(&mut 放射輝度, &mut 通過率, 媒体, 透過率表, 多重散乱表, 幾何, 位置, 区間長, 位相);
    }
    // 積分幅の総和が経路長に等しいため、ここへ渡る通過率は観測点から地表までの全経路ぶんである。
    if 地表まで > 0.0 && 経路長 == 地表まで {
        let 地表位置 = 進む(幾何.観測位置, 幾何.視線, 地表まで);
        地面の照り返しを足す(&mut 放射輝度, 媒体, 透過率表, 地表位置, 幾何.太陽, 通過率);
    }
    Ok(放射輝度)
}

/// 散乱角の余弦から、空気分子と浮遊粒子の位相関数値を求める。
/// 余弦は視線と太陽の向きの内積である。入ってくる光子の向きは太陽の逆、出ていく向きは視線の逆であり、
/// 2つの逆向きの内積は元の2つの内積に等しい(参照: Bruneton 2017実装の`GetSkyRadiance`の`nu`)。
fn 位相の組を求める(媒体: &大気散乱媒体, 幾何: &視線の幾何) -> Result<[f64; 2], 大気数学エラー> {
    let 余弦 = 散乱角余弦::生成する(narrowing::実数へ狭める(内積(幾何.視線, 幾何.太陽).clamp(-1.0, 1.0)))?;
    Ok([
        f64::from(レイリー位相関数(余弦).毎ステラジアン()),
        f64::from(ミー位相関数(媒体.位相非対称係数(), 余弦).毎ステラジアン()),
    ])
}
