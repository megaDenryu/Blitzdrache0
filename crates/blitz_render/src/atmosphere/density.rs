//! 高度から規格化密度を求める工程。受け取るのは密度分布と地表からの高さ、返すのは0以上1以下の密度である。

use blitz_math::メートル;

use super::narrowing;
use super::{密度分布, 規格化密度};

/// 高度が属する層を選び、その層の式を評価して0以上1以下へ切り詰める。
pub fn 規格化密度を求める(分布: &密度分布, 高度: メートル) -> 規格化密度 {
    規格化密度::検証済みの値から(narrowing::実数へ狭める(規格化密度の生値(分布, f64::from(高度.値()))))
}

/// 光学距離の積分が標本点ごとに呼ぶため、単位型を経由せずf64のまま返す入口を持つ。
pub(super) fn 規格化密度の生値(分布: &密度分布, 高度: f64) -> f64 {
    let 層一覧 = 分布.層();
    let 層 = if 高度 < f64::from(層一覧[0].幅().値()) {
        層一覧[0]
    } else {
        層一覧[1]
    };
    // 指数項が0の層で指数を評価すると、高度が大きいとき0と無限大の積になってNaNが出る。
    // 指数項が0であることは「この層は指数分布を持たない」という意味であるため、項ごと落とす。
    let 指数寄与 = if 層.指数項() == 0.0 {
        0.0
    } else {
        f64::from(層.指数項()) * (f64::from(層.指数尺度().値()) * 高度).exp()
    };
    let 値 = 指数寄与 + f64::from(層.線形項().値()) * 高度 + f64::from(層.定数項());
    値.clamp(0.0, 1.0)
}
