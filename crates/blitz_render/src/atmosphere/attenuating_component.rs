//! 視線に沿って光を減らす成分ひとつぶん。消散係数と、その係数が高さ方向にどう薄まるかの分布の組。

use super::{密度分布, 消散係数RGB};

/// 消散係数と密度分布を1つに束ねたもの。光学距離は密度分布だけで決まり、光学的深さはそれに消散係数を掛けて決まる。
/// 空気分子・浮遊粒子・吸収層のいずれもこの同じ形をとるため、3つの成分で型を分けない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 減衰成分 {
    消散係数: 消散係数RGB,
    密度分布: 密度分布,
}

impl 減衰成分 {
    /// 消散係数も密度分布も自身の生成で不変条件を検証済みであるため、束ねる操作は失敗しない。
    pub fn 生成する(消散係数: 消散係数RGB, 密度分布: 密度分布) -> Self {
        Self { 消散係数, 密度分布 }
    }

    pub fn 消散係数(&self) -> 消散係数RGB {
        self.消散係数
    }

    pub fn 密度分布(&self) -> 密度分布 {
        self.密度分布
    }
}
