//! 視線に沿って光がどれだけ失われるかを決める媒体。惑星の2つの半径と、光を減らす3つの成分からなる。

use blitz_math::メートル;

use crate::atmosphere::{大気数学エラー, 減衰成分};

/// 透過率を決めるために要る大気の入力一式。
/// `blitz_engine`の大気媒体方針を、数学が使う形へ落としたものである。方針が持つ尺度高度はここでは密度分布へ、
/// ミーの散乱係数と吸収係数はその和である消散係数へ畳まれている。方針の型をそのまま受け取らないのは、
/// このクレートが上位のエンジン層に依存しないという封じ込めの規律による。
/// 不変条件: 下端半径は有限かつ正であり、上端半径より小さい。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 消散媒体 {
    下端半径: メートル,
    上端半径: メートル,
    レイリー: 減衰成分,
    ミー: 減衰成分,
    吸収: 減衰成分,
}

impl 消散媒体 {
    pub fn 生成する(
        下端半径: メートル,
        上端半径: メートル,
        レイリー: 減衰成分,
        ミー: 減衰成分,
        吸収: 減衰成分,
    ) -> Result<Self, 大気数学エラー> {
        for (項目, 半径) in [("惑星下端半径", 下端半径), ("大気上端半径", 上端半径)] {
            if !半径.値().is_finite() || 半径.値() <= 0.0 {
                return Err(大気数学エラー::値域外(項目, 半径.値()));
            }
        }
        if 下端半径 >= 上端半径 {
            return Err(大気数学エラー::値域外("大気上端半径", 上端半径.値()));
        }
        Ok(Self {
            下端半径,
            上端半径,
            レイリー,
            ミー,
            吸収,
        })
    }

    pub fn 下端半径(&self) -> メートル {
        self.下端半径
    }

    pub fn 上端半径(&self) -> メートル {
        self.上端半径
    }

    pub fn レイリー(&self) -> 減衰成分 {
        self.レイリー
    }

    pub fn ミー(&self) -> 減衰成分 {
        self.ミー
    }

    pub fn 吸収(&self) -> 減衰成分 {
        self.吸収
    }

    /// 光を減らす3つの成分を、光学的深さを足し合わせる順に並べたもの。
    pub fn 成分一覧(&self) -> [減衰成分; 3] {
        [self.レイリー, self.ミー, self.吸収]
    }
}
