//! 視線へ光を足す側の大気。光を減らす消散媒体に、散乱の強さと向きの偏り、地面の反射率を足したもの。

use crate::atmosphere::{位相非対称係数, 地表反射率RGB, 大気数学エラー, 消散係数RGB, 消散媒体};

/// 多重散乱のベイク済み画像とスカイビューのベイク済み画像が要る大気の入力一式。透過率のベイク済み画像だけを作るなら消散媒体で足りるが、
/// 視線へ光が足される量は消散のうち散乱に回る分で決まるため、散乱係数を別に持つ。
/// 消散媒体を継承でなく保持で束ねるのは、透過率の計算がこの型を知らずに済むようにするためである。
/// 不変条件: 空気分子と浮遊粒子のどちらも、散乱係数が消散係数を成分ごとに上回らない。
/// 上回ると1回の散乱で入射より多くの光が出ることになり、多重散乱の等比級数が発散する。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 大気散乱媒体 {
    消散: 消散媒体,
    レイリー散乱係数: 消散係数RGB,
    ミー散乱係数: 消散係数RGB,
    位相非対称係数: 位相非対称係数,
    地表反射率: 地表反射率RGB,
}

impl 大気散乱媒体 {
    pub fn 生成する(
        消散: 消散媒体,
        レイリー散乱係数: 消散係数RGB,
        ミー散乱係数: 消散係数RGB,
        位相非対称係数: 位相非対称係数,
        地表反射率: 地表反射率RGB,
    ) -> Result<Self, 大気数学エラー> {
        散乱が消散を超えないことを確かめる("レイリー散乱係数", レイリー散乱係数, 消散.レイリー().消散係数())?;
        散乱が消散を超えないことを確かめる("ミー散乱係数", ミー散乱係数, 消散.ミー().消散係数())?;
        Ok(Self {
            消散,
            レイリー散乱係数,
            ミー散乱係数,
            位相非対称係数,
            地表反射率,
        })
    }

    pub fn 消散(&self) -> &消散媒体 {
        &self.消散
    }

    pub fn レイリー散乱係数(&self) -> 消散係数RGB {
        self.レイリー散乱係数
    }

    pub fn ミー散乱係数(&self) -> 消散係数RGB {
        self.ミー散乱係数
    }

    pub fn 位相非対称係数(&self) -> 位相非対称係数 {
        self.位相非対称係数
    }

    pub fn 地表反射率(&self) -> 地表反射率RGB {
        self.地表反射率
    }
}

fn 散乱が消散を超えないことを確かめる(
    項目: &'static str,
    散乱: 消散係数RGB,
    消散: 消散係数RGB,
) -> Result<(), 大気数学エラー> {
    for (散乱成分, 消散成分) in 散乱.成分().into_iter().zip(消散.成分()) {
        if 散乱成分 > 消散成分 {
            return Err(大気数学エラー::値域外(項目, 散乱成分.値()));
        }
    }
    Ok(())
}
