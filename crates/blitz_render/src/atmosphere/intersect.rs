//! 視線と2つの同心球(大気上端・地表)の交差を求める工程。
//! 受け取るのは大気内観測点と天頂余弦、返すのは交点までの距離と地平線の向きである。
//!
//! 観測点から距離dだけ進んだ点の惑星中心からの距離の2乗は`d^2 + 2*r*mu*d + r^2`である。
//! これを目的の半径の2乗と等しいと置いた2次方程式の解が交点までの距離になる。

use blitz_math::メートル;

use super::narrowing;
use super::{大気内観測点, 天頂余弦};

/// 大気上端との交点までの距離。観測点が大気の内側にある限り、上向きでも下向きでも必ず1つだけ正の解を持つ。
pub fn 大気上端までの距離(観測点: 大気内観測点<'_>, 天頂余弦: 天頂余弦) -> メートル {
    narrowing::長さへ狭める(上端までの距離の生値(
        f64::from(観測点.媒体().上端半径().値()),
        f64::from(観測点.半径().値()),
        f64::from(天頂余弦.値()),
    ))
}

/// 地表との交点までの距離。視線が地表と交わらないときは値を持たない。
/// 「交わらない」をマジック値で表さないのは、交差距離0が「足元の地面に当たる」という別の意味を持つためである。
pub fn 惑星までの距離(観測点: 大気内観測点<'_>, 天頂余弦: 天頂余弦) -> Option<メートル> {
    let 下端 = f64::from(観測点.媒体().下端半径().値());
    let r = f64::from(観測点.半径().値());
    let mu = f64::from(天頂余弦.値());
    let 判別式 = r * r * (mu * mu - 1.0) + 下端 * 下端;
    if mu >= 0.0 || 判別式 < 0.0 {
        return None;
    }
    Some(narrowing::長さへ狭める((-r * mu - 判別式.sqrt()).max(0.0)))
}

/// 視線が地表に遮られるかどうか。遮られる視線は大気上端まで抜けないため、上端までの光学距離に意味が無くなる。
pub fn 視線が惑星と交差するか(観測点: 大気内観測点<'_>, 天頂余弦: 天頂余弦) -> bool {
    惑星までの距離(観測点, 天頂余弦).is_some()
}

/// 地平線の向きの天頂余弦。観測点から地表へ引いた接線の向きであり、これより下を向く視線が地表と交わる。
/// 観測点が地表以上にあることを大気内観測点が保証するため、平方根の中身は0以上になる。
pub fn 地平線の天頂余弦(観測点: 大気内観測点<'_>) -> 天頂余弦 {
    let 比 = f64::from(観測点.媒体().下端半径().値()) / f64::from(観測点.半径().値());
    let 値 = -(1.0 - 比 * 比).max(0.0).sqrt();
    天頂余弦::検証済みの値から(narrowing::実数へ狭める(値))
}

/// 惑星中心を原点とする位置と単位ベクトルの向きから、半径`球半径`の球との最も近い交点までの距離を求める。
/// 交わらないとき、および交点がすべて背後にあるときは負を返す。多重散乱の経路の終わりと地表の遮蔽がこの値で決まる。
/// 天頂余弦を軸に取る`大気上端までの距離`と別に持つのは、こちらが観測点の姿勢を前提にしない一般の視線を扱うためである。
pub(super) fn 最近の球交差距離(位置: [f64; 3], 向き: [f64; 3], 球半径: f64) -> f64 {
    let b = 2.0 * (向き[0] * 位置[0] + 向き[1] * 位置[1] + 向き[2] * 位置[2]);
    let c = 位置[0] * 位置[0] + 位置[1] * 位置[1] + 位置[2] * 位置[2] - 球半径 * 球半径;
    let 判別式 = b * b - 4.0 * c;
    if 判別式 < 0.0 {
        return -1.0;
    }
    let 根 = 判別式.sqrt();
    let 手前 = (-b - 根) / 2.0;
    let 奥 = (-b + 根) / 2.0;
    if 奥 < 0.0 {
        return -1.0;
    }
    if 手前 < 0.0 { 奥 } else { 手前 }
}

pub(super) fn 上端までの距離の生値(上端半径: f64, 半径: f64, 天頂余弦: f64) -> f64 {
    let 判別式 = 半径 * 半径 * (天頂余弦 * 天頂余弦 - 1.0) + 上端半径 * 上端半径;
    (-半径 * 天頂余弦 + 判別式.max(0.0).sqrt()).max(0.0)
}
