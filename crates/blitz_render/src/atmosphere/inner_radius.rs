//! 大気の内側にあることを検証済みの、惑星中心から測った観測点の距離。

use blitz_math::メートル;

use super::{大気数学エラー, 消散媒体};

/// 惑星中心から観測点までの距離であって、地表以上・大気上端以下であることを生成時に確かめたもの。
/// この不変条件を型で持つのは、視線と球の交差の判別式が非負になる根拠がこの範囲そのものであり、
/// 範囲を外れた半径を許すと交差距離・光学距離・透過率のすべてが値を返せなくなるためである。
/// この型を作った媒体と、これを渡す先の媒体が同じであることは呼び出し側が保つ。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 大気内半径(f32);

impl 大気内半径 {
    pub fn 生成する(媒体: &消散媒体, 半径: メートル) -> Result<Self, 大気数学エラー> {
        if !半径.値().is_finite() || 半径 < 媒体.下端半径() || 半径 > 媒体.上端半径() {
            return Err(大気数学エラー::値域外("大気内半径", 半径.値()));
        }
        Ok(Self(半径.値()))
    }

    /// 地表からの高さ。密度分布はこの高度を入力に取る。
    pub fn 高度(&self, 媒体: &消散媒体) -> メートル {
        メートル::生成する(self.0) - 媒体.下端半径()
    }

    pub fn 長さ(&self) -> メートル {
        メートル::生成する(self.0)
    }
}
