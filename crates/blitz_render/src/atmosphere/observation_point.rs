//! 大気の内側にあることを検証済みの観測点。惑星中心から測った距離と、その検証に使った媒体を一体で持つ。

use blitz_math::メートル;

use super::{大気数学エラー, 消散媒体};

/// 大気の内側にある観測点。半径が地表以上・大気上端以下であることを生成時に確かめ、確かめた相手の媒体を保持する。
/// この不変条件を型で持つのは、視線と球の交差の判別式が非負になる根拠がこの範囲そのものであり、範囲を外れた
/// 半径を許すと交差距離・光学距離・透過率のすべてが値を返せなくなるためである。
/// 半径だけを持たず媒体への参照を一緒に持つのは、半径と媒体が別々の引数だと、ある媒体で検証した半径を別の媒体の
/// 計算へ渡せてしまい、「地表以上・上端以下」という説明がこの値について成り立たなくなるためである。
/// 媒体を複製せず借りるのは、LUTのテクセルごとに観測点を作る使い方で媒体の複製が積み上がるのを避けるためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 大気内観測点<'媒体> {
    媒体: &'媒体 消散媒体,
    半径: f32,
}

impl<'媒体> 大気内観測点<'媒体> {
    pub fn 生成する(媒体: &'媒体 消散媒体, 半径: メートル) -> Result<Self, 大気数学エラー> {
        if !半径.値().is_finite() || 半径 < 媒体.下端半径() || 半径 > 媒体.上端半径() {
            return Err(大気数学エラー::値域外("大気内観測点", 半径.値()));
        }
        Ok(Self {
            媒体, 半径: 半径.値()
        })
    }

    /// この観測点が属する媒体。交差も光学距離も透過率も、この媒体だけを見て計算する。
    pub fn 媒体(&self) -> &'媒体 消散媒体 {
        self.媒体
    }

    /// 地表からの高さ。密度分布はこの高度を入力に取る。
    pub fn 高度(&self) -> メートル {
        メートル::生成する(self.半径) - self.媒体.下端半径()
    }

    /// 惑星中心から測った距離。
    pub fn 半径(&self) -> メートル {
        メートル::生成する(self.半径)
    }
}
