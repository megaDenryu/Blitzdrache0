//! スカイビューLUTを1枚焼く条件。観測点の高度と太陽の天頂余弦の組である。

use blitz_math::メートル;

use super::{大気数学エラー, 天頂余弦, 消散媒体};

/// スカイビューLUTの中身を決める、大気以外の2つの入力。
///
/// 太陽の方位角を持たないのは、LUTの横軸が太陽に対する相対方位であり、球対称の大気では太陽の方位を
/// どこへ置いても同じ表になるためである。太陽の放射照度も持たない。放射照度は線形に効くため、
/// LUTは1としたときの値を保ち、描画側が掛ける。
/// 観測点を半径でなく地表からの高度で持つのは、この値が世界の方針から来るものであり、
/// 惑星半径を足す操作を媒体を知る場所へ寄せるためである。
/// 不変条件: 高度は有限かつ0以上である。上端との関係は媒体を伴う`観測半径`で切り詰める。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct スカイビュー観測条件 {
    観測高度: メートル,
    太陽天頂余弦: 天頂余弦,
}

impl スカイビュー観測条件 {
    pub fn 生成する(観測高度: メートル, 太陽天頂余弦: 天頂余弦) -> Result<Self, 大気数学エラー> {
        if !観測高度.値().is_finite() || 観測高度.値() < 0.0 {
            return Err(大気数学エラー::値域外("スカイビューの観測高度", 観測高度.値()));
        }
        Ok(Self {
            観測高度, 太陽天頂余弦
        })
    }

    pub fn 観測高度(&self) -> メートル {
        self.観測高度
    }

    pub fn 太陽天頂余弦(&self) -> 天頂余弦 {
        self.太陽天頂余弦
    }

    /// 惑星中心から測った観測点の距離。大気の外を指す高度は上端へ切り詰める。
    /// 切り詰めるのは、視線と球の交差の判別式が非負である根拠が「観測点が大気の内側にある」ことだからである。
    /// 大気より上の観測点は空を下向きにしか見ないため、この段では扱わない(参照: 設計文書「大気LUT方式の設計」)。
    pub fn 観測半径(&self, 媒体: &消散媒体) -> メートル {
        let 半径 = 媒体.下端半径() + self.観測高度;
        if 半径 > 媒体.上端半径() { 媒体.上端半径() } else { 半径 }
    }
}
