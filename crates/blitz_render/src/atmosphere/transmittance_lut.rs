//! 透過率LUTの1テクセルの値を求める工程。受け取るのは媒体とテクセルの添字、返すのはそのテクセルの透過率である。
//!
//! これがLUTの内容の正本であり、`shaders/atmosphere_transmittance.slang`はこの式の写しである。
//! CPU側に正本を置くのは、写像の逆写像との往復・値域・単調性をユニットテストで検査できるようにするためである
//! (カスケードシャドウの帯ブレンドで`cascade/blend.rs`が正本、`shaders/cascade_shadow.slang`が写しであるのと同じ関係)。

use super::transmittance_mapping::{テクセル中心のuv, 透過率lutの視線を求める};
use super::{上端までの透過率, 大気LUT解像度, 大気数学エラー, 消散媒体, 積分標本数, 透過率RGB};

/// 透過率lutを焼くときに経路を刻む区間の数。Hillaire 2020実装の透過率LUTと同じ40区間を採る。
/// シェーダーの写しも同じ値を持ち、標本数が食い違うと同じ式でも結果がずれるため、GPU読み戻し検査がこの一致を見る。
const 標本区間数: u32 = 40;

/// テクセルの添字からそのテクセルの透過率を求める。視線が地表と交わる向きでも積分は大気上端まで進むため、
/// この値は地面に遮られる視線について物理的な意味を持たない。Hillaire 2020のパラメータ化は地平線より下の
/// 向きをLUTの外へ追い出すため、そのようなテクセルは生じない。
pub fn 透過率lutのテクセル値(
    媒体: &消散媒体, 解像度: 大気LUT解像度, 横: u32, 縦: u32
) -> Result<透過率RGB, 大気数学エラー> {
    let 視線 = 透過率lutの視線を求める(
        媒体,
        テクセル中心のuv(横, 解像度.透過率の幅()),
        テクセル中心のuv(縦, 解像度.透過率の高さ()),
    )?;
    Ok(上端までの透過率(視線.観測点, 視線.天頂余弦, 積分標本数::生成する(標本区間数)?))
}

/// LUT全体を走査して各テクセルの透過率を求める。GPUが焼いた結果と突き合わせる期待値がこれである。
/// テクセルの並びは横方向が先で、GPUの画像を行優先で読み戻した並びと一致する。
pub fn 透過率lutを焼く(媒体: &消散媒体, 解像度: 大気LUT解像度) -> Result<Vec<透過率RGB>, 大気数学エラー> {
    let mut 一覧 = Vec::with_capacity(解像度.透過率のテクセル数());
    for 縦 in 0..解像度.透過率の高さ() {
        for 横 in 0..解像度.透過率の幅() {
            一覧.push(透過率lutのテクセル値(媒体, 解像度, 横, 縦)?);
        }
    }
    Ok(一覧)
}
