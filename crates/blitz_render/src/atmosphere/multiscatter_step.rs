//! 多重散乱の経路上で1区間ぶんを積む操作と、経路が地表で終わるときの地面の照り返し。
//! 受け取るのは積分の途中経過と区間の条件、返り値は無く、渡された途中経過を進めるだけである。
//!
//! 区間の中で消散が一定であるとみなし、閉形式で積む。散乱の総量だけを積む`残存率`が、
//! 「1回の散乱を経ても行き先を失わずに残る割合」であり、これを等比級数の公比として使う。

use std::f64::consts::PI;

use super::medium_sample::媒体標本;
use super::sun_visibility::{太陽が地表に遮られるか, 太陽への透過率を引く};
use super::transmittance_table::透過率表;
use super::vector3::{内積, 単位化};
use super::大気散乱媒体;

pub(super) struct 区間の条件 {
    pub(super) 位置: [f64; 3],
    pub(super) 太陽: [f64; 3],
    pub(super) 刻み: f64,
}

pub(super) fn 区間を積む(
    放射輝度: &mut [f64; 3],
    残存率: &mut [f64; 3],
    通過率: &mut [f64; 3],
    媒体: &大気散乱媒体,
    透過率表: &透過率表,
    条件: &区間の条件,
) {
    let 標本 = 媒体標本::求める(媒体, 条件.位置);
    let 太陽への透過率 = if 太陽が地表に遮られるか(媒体, 条件.位置, 条件.太陽) {
        [0.0; 3]
    } else {
        太陽への透過率を引く(媒体, 透過率表, 条件.位置, 条件.太陽)
    };
    let 等方位相 = 1.0 / (4.0 * PI);
    for 添字 in 0..3 {
        let 消散 = 標本.消散係数[添字];
        let 区間透過率 = (-消散 * 条件.刻み).exp();
        if 消散 > 0.0 {
            let 散乱源 = 太陽への透過率[添字] * 標本.散乱係数[添字] * 等方位相;
            放射輝度[添字] += 通過率[添字] * (散乱源 - 散乱源 * 区間透過率) / 消散;
            let 残り = 標本.散乱係数[添字];
            残存率[添字] += 通過率[添字] * (残り - 残り * 区間透過率) / 消散;
        }
        通過率[添字] *= 区間透過率;
    }
}

/// 視線が地表で終わるとき、地面が拡散反射で返す光を足す。
/// 遮蔽判定を通さずに透過率を引くのは、地表そのものにある点が自分の足元と交わるためである
/// (詳細は`sun_visibility`)。照り返しの向きの妥当性は入射余弦が受け持つ。
pub(super) fn 地面の照り返しを足す(
    放射輝度: &mut [f64; 3],
    媒体: &大気散乱媒体,
    透過率表: &透過率表,
    地表位置: [f64; 3],
    太陽: [f64; 3],
    通過率: [f64; 3],
) {
    let 太陽への透過率 = 太陽への透過率を引く(媒体, 透過率表, 地表位置, 太陽);
    let Some(上向き) = 単位化(地表位置) else {
        return;
    };
    let 入射余弦 = 内積(上向き, 太陽).clamp(0.0, 1.0);
    let アルベド = 媒体.地表アルベド().成分();
    for 添字 in 0..3 {
        放射輝度[添字] += 太陽への透過率[添字] * 通過率[添字] * 入射余弦 * f64::from(アルベド[添字]) / PI;
    }
}
