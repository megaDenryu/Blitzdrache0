//! CPU側に焼いた透過率LUTと、そこからの双一次補間の標本取り。
//! 受け取るのはテクセル座標のUV、返すのはその位置の透過率である。
//!
//! 多重散乱の計算がこの表を引くのは、GPU側の多重散乱シェーダーが透過率LUTをサンプラーで引くからである。
//! CPUが解析的に透過率を求め直すと、補間の有無だけで両者がずれ、写しの誤りと区別できなくなる。
//! 補間の規則(テクセル中心を標本点とし、外側は端のテクセルへ張り付ける)はVulkanのLINEARフィルタと
//! CLAMP_TO_EDGEアドレスモードに合わせてある。

use super::{大気LUT解像度, 大気数学エラー, 消散媒体, 透過率RGB, 透過率lutを焼く};

pub struct 透過率表 {
    解像度: 大気LUT解像度,
    テクセル一覧: Vec<透過率RGB>,
}

impl 透過率表 {
    pub fn 焼く(媒体: &消散媒体, 解像度: 大気LUT解像度) -> Result<Self, 大気数学エラー> {
        Ok(Self {
            解像度,
            テクセル一覧: 透過率lutを焼く(媒体, 解像度)?,
        })
    }

    pub fn テクセル一覧(&self) -> &[透過率RGB] {
        &self.テクセル一覧
    }

    /// UVの位置の透過率を双一次補間で求める。計算はf64で行い、多重散乱の積分がそのまま使う。
    pub(super) fn 標本を引く(&self, 横uv: f64, 縦uv: f64) -> [f64; 3] {
        let 幅 = self.解像度.透過率の幅();
        let 高さ = self.解像度.透過率の高さ();
        let (左, 右, 横比) = 補間の添字と比(横uv, 幅);
        let (上, 下, 縦比) = 補間の添字と比(縦uv, 高さ);
        let 左上 = self.テクセル(左, 上);
        let 右上 = self.テクセル(右, 上);
        let 左下 = self.テクセル(左, 下);
        let 右下 = self.テクセル(右, 下);
        let mut 結果 = [0.0; 3];
        for 添字 in 0..3 {
            let 上辺 = 左上[添字] + (右上[添字] - 左上[添字]) * 横比;
            let 下辺 = 左下[添字] + (右下[添字] - 左下[添字]) * 横比;
            結果[添字] = 上辺 + (下辺 - 上辺) * 縦比;
        }
        結果
    }

    fn テクセル(&self, 横: u32, 縦: u32) -> [f64; 3] {
        let 幅 = usize::try_from(self.解像度.透過率の幅()).unwrap_or(0);
        let 横 = usize::try_from(横).unwrap_or(0);
        let 縦 = usize::try_from(縦).unwrap_or(0);
        let Some(値) = self.テクセル一覧.get(縦 * 幅 + 横) else {
            panic!("透過率表の範囲外を引いた(横{横} 縦{縦})。添字の切り詰めが効いていない");
        };
        値.成分().map(f64::from)
    }
}

/// テクセル中心を標本点とする双一次補間の、両隣の添字と混ぜ具合。範囲の外は端のテクセルへ張り付ける。
fn 補間の添字と比(uv: f64, 辺の長さ: u32) -> (u32, u32, f64) {
    let 位置 = uv * f64::from(辺の長さ) - 0.5;
    let 最大添字 = 辺の長さ - 1;
    let 手前 = 床の添字(位置, 最大添字);
    let 比 = (位置 - f64::from(手前)).clamp(0.0, 1.0);
    (手前, (手前 + 1).min(最大添字), 比)
}

/// 実数の位置以下で最大の添字を、範囲の外を端へ張り付けたうえで返す。
///
/// 二分探索で求めるのは、浮動小数から整数への安全な標準変換が無く(`as`キャストは規約で禁止)、
/// 既存の文字列往復による丸めはテクセルごとに何度も呼ぶこの経路には遅すぎるためである。
/// 辺の長さは256以下であり、比較は8回程度で終わる。
fn 床の添字(位置: f64, 最大添字: u32) -> u32 {
    if 位置.is_nan() || 位置 <= 0.0 {
        return 0;
    }
    if 位置 >= f64::from(最大添字) {
        return 最大添字;
    }
    let mut 下 = 0u32;
    let mut 上 = 最大添字;
    while 下 < 上 {
        let 中 = 下 + (上 - 下).div_ceil(2);
        if f64::from(中) <= 位置 {
            下 = 中;
        } else {
            上 = 中 - 1;
        }
    }
    下
}
