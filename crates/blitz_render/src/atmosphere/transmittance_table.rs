//! CPU側に焼いた透過率LUTと、そこからの双一次補間の標本取り。
//! 受け取るのはテクセル座標のUV、返すのはその位置の透過率である。
//!
//! 多重散乱とスカイビューの計算がこの表を引くのは、GPU側の生成シェーダーが透過率LUTをサンプラーで引くからである。
//! CPUが解析的に透過率を求め直すと、補間の有無だけで両者がずれ、写しの誤りと区別できなくなる。
//! 補間の規則(テクセル中心を標本点とし、外側は端のテクセルへ張り付ける)は`bilinear`が持つ。

use super::{bilinear, 大気LUT解像度, 大気数学エラー, 消散媒体, 透過率RGB, 透過率lutを焼く};

pub struct 透過率表 {
    解像度: 大気LUT解像度,
    テクセル一覧: Vec<透過率RGB>,
}

impl 透過率表 {
    pub fn 焼く(媒体: &消散媒体, 解像度: 大気LUT解像度) -> Result<Self, 大気数学エラー> {
        Ok(Self {
            解像度,
            テクセル一覧: 透過率lutを焼く(媒体, 解像度)?,
        })
    }

    pub fn テクセル一覧(&self) -> &[透過率RGB] {
        &self.テクセル一覧
    }

    /// UVの位置の透過率を双一次補間で求める。計算はf64で行い、多重散乱とスカイビューの積分がそのまま使う。
    pub(super) fn 標本を引く(&self, 横uv: f64, 縦uv: f64) -> [f64; 3] {
        let (左, 右, 横比) = bilinear::添字と比(横uv, self.解像度.透過率の幅());
        let (上, 下, 縦比) = bilinear::添字と比(縦uv, self.解像度.透過率の高さ());
        bilinear::混ぜる(
            self.テクセル(左, 上),
            self.テクセル(右, 上),
            self.テクセル(左, 下),
            self.テクセル(右, 下),
            横比,
            縦比,
        )
    }

    fn テクセル(&self, 横: u32, 縦: u32) -> [f64; 3] {
        let 幅 = usize::try_from(self.解像度.透過率の幅()).unwrap_or(0);
        let 横 = usize::try_from(横).unwrap_or(0);
        let 縦 = usize::try_from(縦).unwrap_or(0);
        let Some(値) = self.テクセル一覧.get(縦 * 幅 + 横) else {
            panic!("透過率表の範囲外を引いた(横{横} 縦{縦})。添字の切り詰めが効いていない");
        };
        値.成分().map(f64::from)
    }
}
