//! 入射方向と散乱後の方向のなす角の余弦。位相関数がどれだけの光をその向きへ振り分けるかを決める唯一の入力。

use crate::atmosphere::大気数学エラー;

/// 光が来た向きと散乱して進む向きの内積。1が前方散乱(そのまま進む)、-1が後方散乱(来た方へ返る)である。
/// 天頂余弦と別の型にするのは、片方が観測点の姿勢に対する視線の角度、もう片方が2つの光線の間の角度であり、
/// 取り違えても値域が同じために実行時には気づけないためである。
/// 不変条件: 有限かつ-1以上1以下である。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 散乱角余弦(f32);

impl 散乱角余弦 {
    pub fn 生成する(値: f32) -> Result<Self, 大気数学エラー> {
        if !値.is_finite() || !(-1.0..=1.0).contains(&値) {
            return Err(大気数学エラー::値域外("散乱角余弦", 値));
        }
        Ok(Self(値))
    }

    pub fn 値(&self) -> f32 {
        self.0
    }
}
