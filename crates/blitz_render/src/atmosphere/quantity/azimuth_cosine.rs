//! 水平面へ落とした視線と太陽のなす角の余弦。スカイビューのベイク済み画像が方位の違いを1つの数で表すときの型。

use crate::atmosphere::大気数学エラー;

/// 視線と太陽をそれぞれ観測点の水平面へ射影し、その2つのなす角の余弦を取った値。
/// 1が太陽と同じ方位、0が真横、-1が反対の方位である。
///
/// 球対称の大気では方位角の絶対値だけが結果に効くため、この1つの数で方位の全域を表せる。
/// 天頂余弦と別の型にするのは、軸の意味が違う2つの余弦を取り違えるとベイク済み画像の横縦が入れ替わり、
/// 絵の上では「太陽の側が明るい」という向きだけが静かに壊れるためである。
/// 不変条件: 有限かつ-1以上1以下である。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 方位余弦(f32);

impl 方位余弦 {
    pub fn 生成する(値: f32) -> Result<Self, 大気数学エラー> {
        if !値.is_finite() || !(-1.0..=1.0).contains(&値) {
            return Err(大気数学エラー::値域外("方位余弦", 値));
        }
        Ok(Self(値))
    }

    pub fn 値(&self) -> f32 {
        self.0
    }
}
