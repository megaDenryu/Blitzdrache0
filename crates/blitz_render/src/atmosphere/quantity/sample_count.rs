//! 経路に沿った数値積分を何区間に刻むかの指定。

use crate::atmosphere::大気数学エラー;

/// 台形則で経路を刻む区間の数。区間数がnのとき標本点はn+1個であり、両端の重みが半分になる。
/// 標本数を引数で受け取るのは、参照実装との一致検査には高い標本数を、ベイク済み画像生成には性能に見合う標本数を
/// 同じ関数で使い分けるためである。
/// 不変条件: 1以上である。0では刻み幅が定義できない。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 積分標本数(u32);

impl 積分標本数 {
    pub fn 生成する(値: u32) -> Result<Self, 大気数学エラー> {
        if 値 == 0 {
            return Err(大気数学エラー::整数値域外("積分標本数", 値));
        }
        Ok(Self(値))
    }

    pub fn 区間数(&self) -> u32 {
        self.0
    }
}
