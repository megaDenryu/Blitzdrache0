//! 天空放射輝度供給が答える、太陽円盤を除いた連続な天空放射輝度を赤・緑・青の3成分で表した量。

use crate::atmosphere::大気数学エラー;

/// シーン線形の尺度で表した天空の放射輝度。太陽の放射照度の尺度を掛け、夜間背景を足した後の値である。
/// スカイビュー放射輝度RGBと別の型にするのは、あちらが太陽の明るさを1としたときの伝達率であり、
/// 尺度を掛けたかどうかを取り違えると絵が20倍ずれるためである。
///
/// 物理単位を名乗らないのは、このエンジンの光の強さがまだSI単位へ校正されていないためである
/// (参照: `_doc/設計/放射輝度問い合わせ階層.md`「B. 間接放射輝度場」)。
/// 不変条件: 3成分とも有限かつ0以上である。上限は置かない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 天空放射輝度RGB {
    成分: [f32; 3],
}

impl 天空放射輝度RGB {
    pub fn 生成する(赤: f32, 緑: f32, 青: f32) -> Result<Self, 大気数学エラー> {
        let 成分 = [赤, 緑, 青];
        for 値 in 成分 {
            if !値.is_finite() || 値 < 0.0 {
                return Err(大気数学エラー::値域外("天空放射輝度RGB", 値));
            }
        }
        Ok(Self { 成分 })
    }

    pub fn 成分(&self) -> [f32; 3] {
        self.成分
    }
}
