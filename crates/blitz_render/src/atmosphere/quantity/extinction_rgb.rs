//! 単位長さあたりに光が失われる割合を、赤・緑・青の3成分で表した係数。

use blitz_math::逆メートル;

use crate::atmosphere::大気数学エラー;

/// 密度が最大の高度での消散係数。規格化密度との積がその高度での実効的な消散係数になる。
/// 不変条件: 3成分とも有限かつ0以上である。負の係数は光を進むほど増やす向きになり、物理的に意味を持たない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 消散係数RGB {
    成分: [逆メートル; 3],
}

impl 消散係数RGB {
    pub fn 生成する(赤: 逆メートル, 緑: 逆メートル, 青: 逆メートル) -> Result<Self, 大気数学エラー> {
        let 成分 = [赤, 緑, 青];
        for 値 in 成分 {
            if !値.値().is_finite() || 値.値() < 0.0 {
                return Err(大気数学エラー::値域外("消散係数RGB", 値.値()));
            }
        }
        Ok(Self { 成分 })
    }

    /// 毎メートル単位の3つの生値から作る。文献値がこの単位で表になっているため、変換の手間を境界1箇所へ閉じる。
    pub fn 毎メートルから(赤: f32, 緑: f32, 青: f32) -> Result<Self, 大気数学エラー> {
        Self::生成する(逆メートル::生成する(赤), 逆メートル::生成する(緑), 逆メートル::生成する(青))
    }

    pub fn 成分(&self) -> [逆メートル; 3] {
        self.成分
    }
}
