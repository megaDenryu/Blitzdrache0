//! 太陽の放射照度を1としたときに、ある視線が観測点へ運ぶ空の放射輝度を赤・緑・青の3成分で表した量。

use crate::atmosphere::大気数学エラー;

/// スカイビューのベイク済み画像が保持する値。太陽の明るさを掛ける前の伝達率であるため、太陽の放射照度が変わっても焼き直す必要が無い。
/// 太陽円盤の直射はこの値に含まない。円盤は視線の立体角のごく一部だけを占め、ベイク済み画像の1テクセルへ混ぜると
/// テクセル全体が太陽の明るさで塗られてしまうため、描画側が別項として足す。
/// 不変条件: 3成分とも有限かつ0以上である。負の放射輝度は物理的に意味を持たない。
/// 上限を置かないのは、地表反射率が高い大気では散乱の合計が太陽の放射照度に対して1を超えうるためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct スカイビュー放射輝度RGB {
    成分: [f32; 3],
}

impl スカイビュー放射輝度RGB {
    pub fn 生成する(赤: f32, 緑: f32, 青: f32) -> Result<Self, 大気数学エラー> {
        let 成分 = [赤, 緑, 青];
        for 値 in 成分 {
            if !値.is_finite() || 値 < 0.0 {
                return Err(大気数学エラー::値域外("スカイビュー放射輝度RGB", 値));
            }
        }
        Ok(Self { 成分 })
    }

    pub fn 成分(&self) -> [f32; 3] {
        self.成分
    }
}
