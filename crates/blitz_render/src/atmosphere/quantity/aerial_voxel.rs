//! 空中遠近ボリュームの1ボクセルが保持する量。カメラからある距離までの経路が加えた散乱と、その経路が残す透過率の組である。

use crate::atmosphere::大気数学エラー;

/// 空中遠近ボリュームの1ボクセルの値。太陽の放射照度を1として焼くため、描画側が尺度を掛ける。
///
/// 散乱を3成分で持ち透過率を1成分で持つのは、加える光の色が方向と経路で大きく変わる一方、
/// 面の色がどれだけ残るかの色依存は数百メートルから数キロメートルの経路では小さいためである。
/// 代表透過率は3成分の等重み平均であり、色付き透過率との差が参照検証で許容外になったときだけ
/// 散乱RGBと透過率RGBの2ボリュームへ拡張する(参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「ベイク済み画像構成」)。
///
/// 不変条件: 散乱の3成分は有限かつ0以上であり、代表透過率は有限かつ0以上1以下である。
/// 散乱に上限を置かないのは、地表反射率が高い大気では散乱の合計が太陽の放射照度に対して1を超えうるためである。
/// 透過率に上限を置くのは、Beer-Lambertの法則により経路が光を増やすことがないためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 空中遠近ボクセル値 {
    散乱: [f32; 3],
    代表透過率: f32,
}

impl 空中遠近ボクセル値 {
    pub fn 生成する(散乱: [f32; 3], 代表透過率: f32) -> Result<Self, 大気数学エラー> {
        for 値 in 散乱 {
            if !値.is_finite() || 値 < 0.0 {
                return Err(大気数学エラー::値域外("空中遠近の散乱", 値));
            }
        }
        if !代表透過率.is_finite() || !(0.0..=1.0).contains(&代表透過率) {
            return Err(大気数学エラー::値域外("空中遠近の代表透過率", 代表透過率));
        }
        Ok(Self { 散乱, 代表透過率 })
    }

    pub fn 散乱の成分(&self) -> [f32; 3] {
        self.散乱
    }

    pub fn 代表透過率(&self) -> f32 {
        self.代表透過率
    }
}
