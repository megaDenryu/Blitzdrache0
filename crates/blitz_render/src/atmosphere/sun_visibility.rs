//! ある点から太陽がどう見えるかを担う工程。受け取るのは点と太陽または視線の向き、
//! 返すのはその向きの透過率、または惑星に遮られるかどうかである。
//!
//! 透過率と遮蔽を分けて持つのは、地面の照り返しが透過率だけを遮蔽判定なしで使うからである。
//! 地表そのものにある点は自分の足元と交わるため、遮蔽判定を通すと照り返しが常に消える。
//!
//! 呼び出し元は2つある。LUTを焼く積分は惑星中心を原点とする生ベクトルで経路の標本点ごとに引き、
//! 空パスは検証済みの観測点と天頂余弦で画素ごとに引く。同じ「太陽の見え方」を2つの入口で表すのは、
//! 前者が1テクセルあたり何十回も呼ばれて値オブジェクトの生成が積み上がるためである。

use super::intersect::{最近の球交差距離, 視線が惑星と交差するか};
use super::narrowing;
use super::transmittance_mapping::{透過率lutのuvの生値, 透過率lutのuvを求める};
use super::transmittance_table::透過率表;
use super::vector3::{内積, 単位化, 長さ};
use super::{大気内観測点, 大気散乱媒体, 天頂余弦, 透過率RGB};

/// 地表の遮蔽を判定するときに遮蔽球の半径をこの量だけ縮める。判定する点が地表そのものにあるとき、
/// 自分の足元との交差を拾って常に影と答えることを避ける。
/// 標本点を動かす形を採らないのは、余裕より低い高度の点が惑星の内部へ入る形しか作れないためである。
/// 内向きへ動かせば点が球の内部に入り、球の内部から出るレイは向きに関わらず必ず正の遠方交点を持つため、
/// 太陽が天頂にあっても遮蔽ありと答える。外向きへ動かせば判定する点が媒体を評価した点と食い違う。
/// 球の側だけを縮めれば、点の半径と向きはそのまま判定へ渡る。
pub(super) const 遮蔽球を縮める半径メートル: f64 = 10.0;

/// その位置から太陽へ向かう向きの透過率。表を引くだけであり、惑星による遮蔽はここでは見ない。
pub(super) fn 太陽への透過率を引く(
    媒体: &大気散乱媒体, 透過率表: &透過率表, 位置: [f64; 3], 太陽: [f64; 3]
) -> [f64; 3] {
    let Some(上向き) = 単位化(位置) else {
        return [0.0; 3];
    };
    let 下端 = f64::from(媒体.消散().下端半径().値());
    let 上端 = f64::from(媒体.消散().上端半径().値());
    let [横uv, 縦uv] = 透過率lutのuvの生値(下端, 上端, 長さ(位置), 内積(上向き, 太陽).clamp(-1.0, 1.0));
    透過率表.標本を引く(横uv, 縦uv)
}

/// その位置から太陽へ向かう視線が惑星に遮られるか。
///
/// 注意: 縮めた球で判定するため、遮蔽が始まる太陽の高度が真の地平線より約0.1度だけ低い方へずれる
/// (半径10メートルぶんの弦の深さに対応する角度)。真偽が切り替わる瞬間に足される直射は、地平線をかすめる
/// 長い経路を通った透過率(地表では緑で1パーセント台)まで減っているため、このずれが作る段差も同じ桁に収まる。
pub(super) fn 太陽が地表に遮られるか(媒体: &大気散乱媒体, 位置: [f64; 3], 太陽: [f64; 3]) -> bool {
    let 遮蔽球半径 = f64::from(媒体.消散().下端半径().値()) - 遮蔽球を縮める半径メートル;
    最近の球交差距離(位置, 太陽, 遮蔽球半径) >= 0.0
}

/// 太陽円盤の画素に掛かる透過率を求める。視線が惑星と交わる向きは直射が届かないため0を返す。
///
/// 円盤の中心方向でなく画素ごとの視線で評価するのは、円盤が有限の角半径を持つためである。円盤が地平線を
/// またぐ間、上側の画素は大気上端へ抜けるのに下側の画素は惑星へ入る。中心方向で1つの値を作ると円盤全体が
/// 同じ明るさになり、欠けを中心角の補間でしか表せない。
///
/// 惑星の遮蔽を滑らかにせず真偽で切るのは、惑星の縁が幾何としての硬い境界であり、画素ごとに判定すれば
/// 地平線をまたぐ円盤が下側だけ欠ける形へ自然に落ちるためである。円盤の縁のジャギーは角半径の内外を
/// 滑らかにする被覆率が受け持ち、この工程は受け持たない。
///
/// 注意: この工程は`shaders/sky_atmosphere.slang`の円盤項の写しを持つ。ここが正本である。
pub fn 太陽円盤の画素に掛かる透過率を求める(
    観測点: 大気内観測点<'_>, 視線天頂余弦: 天頂余弦, 透過率表: &透過率表
) -> 透過率RGB {
    if 視線が惑星と交差するか(観測点, 視線天頂余弦) {
        return 透過率RGB::検証済みの成分から([0.0; 3]);
    }
    let [横uv, 縦uv] = 透過率lutのuvを求める(観測点, 視線天頂余弦);
    let 成分 = 透過率表.標本を引く(f64::from(横uv), f64::from(縦uv));
    // 前提: 透過率表のテクセルは0以上1以下であり、双一次補間はその凸結合であるため範囲を出ない。
    透過率RGB::検証済みの成分から(成分.map(narrowing::実数へ狭める))
}
