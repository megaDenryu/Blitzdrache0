//! スカイビューLUTのテクセル座標と、視線の天頂余弦・太陽との方位余弦との行き来を担う工程。
//! 受け取るのは単位位置の組(または視線)、返すのは対応する視線(または単位位置の組)である。
//!
//! 縦軸を天頂余弦の等間隔に取らず、地平線を境に2つの区間へ分け、それぞれの中で境界へ標本を寄せる。
//! 空の放射輝度は地平線付近で急に変わるうえ、地平線の位置は観測高度で動くためである。
//! 横軸は太陽方位余弦を平方根で刻み、太陽の側に標本を寄せる。太陽周辺の前方散乱が方位で急に変わるためである。
//! 参照: Sebastien Hillaire, "A Scalable and Production Ready Sky and Atmosphere Rendering Technique" (EGSR 2020)の
//! `UvToSkyViewLutParams`および`SkyViewLutParamsToUv`。
//!
//! 注意: この写像は`shaders/atmosphere_skyview_mapping.slang`の写しを持つ。ここが正本であり、ずれるとLUTを焼いた
//! 座標と引く座標が食い違って空の色が静かにずれる。往復と軸の意味は`atmosphere_tests`が、CPUとGPUの一致は
//! GPU読み戻し検査が代表テクセルで確かめる。

use crate::atmosphere::narrowing;
use crate::atmosphere::{大気数学エラー, 天頂余弦, 方位余弦, 消散媒体};

/// LUTの1テクセルが表す視線。天頂からの角と、太陽に対する方位の2つで決まる。
#[derive(Debug, Clone, Copy)]
pub struct スカイビューLUT視線 {
    pub 視線天頂余弦: 天頂余弦,
    pub 太陽方位余弦: 方位余弦,
}

/// 観測点から見た天頂と地平線と天底の角の配置。縦軸の目盛りがこの3つで決まる。
struct 縦軸の配置 {
    /// 天頂から地平線までの角。観測高度が上がるほど大きくなり、地表では直角である。
    天頂から地平線まで: f64,
    /// 地平線から天底までの角。天頂から地平線までの角との和は必ず円周角の半分である。
    地平線から天底まで: f64,
}

/// 単位位置の組から視線を求める。横が太陽に対する方位、縦が天頂から天底への向きである。
/// 縦が0.5未満なら地面と交わらない向き、0.5以上なら地面と交わる向きになる。
pub fn スカイビューlutの視線を求める(
    媒体: &消散媒体,
    観測半径: f64,
    横位置: f64,
    縦位置: f64,
) -> Result<スカイビューLUT視線, 大気数学エラー> {
    let 配置 = 縦軸の配置を求める(媒体, 観測半径);
    let 天頂角 = if 縦位置 < 0.5 {
        let 寄せ = 1.0 - (1.0 - 2.0 * 縦位置) * (1.0 - 2.0 * 縦位置);
        配置.天頂から地平線まで * 寄せ
    } else {
        let 寄せ = (2.0 * 縦位置 - 1.0) * (2.0 * 縦位置 - 1.0);
        配置.天頂から地平線まで + 配置.地平線から天底まで * 寄せ
    };
    Ok(スカイビューLUT視線 {
        視線天頂余弦: 天頂余弦::生成する(narrowing::実数へ狭める(天頂角.cos().clamp(-1.0, 1.0)))?,
        太陽方位余弦: 方位余弦::生成する(narrowing::実数へ狭める((1.0 - 2.0 * 横位置 * 横位置).clamp(-1.0, 1.0)))?,
    })
}

/// 視線から単位位置の組を求める。`スカイビューlutの視線を求める`の逆写像である。
/// 地平線のどちら側かは視線天頂余弦と地平線の余弦の比較だけで決まるため、呼び出し元は交差判定を渡さない。
pub fn スカイビューlutの単位位置を求める(媒体: &消散媒体, 観測半径: f64, 視線: スカイビューLUT視線) -> [f64; 2] {
    let 配置 = 縦軸の配置を求める(媒体, 観測半径);
    let 天頂角 = f64::from(視線.視線天頂余弦.値()).clamp(-1.0, 1.0).acos();
    let 縦位置 = if 天頂角 <= 配置.天頂から地平線まで {
        let 比 = 割る(天頂角, 配置.天頂から地平線まで);
        0.5 * (1.0 - (1.0 - 比).max(0.0).sqrt())
    } else {
        let 比 = 割る(天頂角 - 配置.天頂から地平線まで, 配置.地平線から天底まで);
        0.5 + 0.5 * 比.max(0.0).sqrt()
    };
    let 横位置 = ((1.0 - f64::from(視線.太陽方位余弦.値())) * 0.5).max(0.0).sqrt();
    [横位置.clamp(0.0, 1.0), 縦位置.clamp(0.0, 1.0)]
}

/// 観測点から地表へ引いた接線の向きが天頂から何度離れているかを求める。
/// 観測半径が下端半径以上であることは呼び出し元が保証し、平方根の中身は0以上になる。
fn 縦軸の配置を求める(媒体: &消散媒体, 観測半径: f64) -> 縦軸の配置 {
    let 下端 = f64::from(媒体.下端半径().値());
    let 地平線までの弦 = (観測半径 * 観測半径 - 下端 * 下端).max(0.0).sqrt();
    let 地平線から天底まで = 割る(地平線までの弦, 観測半径).clamp(-1.0, 1.0).acos();
    縦軸の配置 {
        天頂から地平線まで: std::f64::consts::PI - 地平線から天底まで,
        地平線から天底まで,
    }
}

/// 分母が0のときに0を返す除算。観測半径が0になるのは惑星中心に観測点を置いた場合だけであり、
/// 大気内観測点の不変条件がそれを禁じているため、ここは丸めで境界へ落ちた場合の備えである。
fn 割る(分子: f64, 分母: f64) -> f64 {
    if 分母 <= 0.0 { 0.0 } else { 分子 / 分母 }
}
