//! 空中遠近ボリュームのボクセル座標と、画面の位置およびカメラからの距離との行き来を担う工程。
//! 受け取るのはボクセルの添字(または距離)、返すのは対応する画面の位置と距離(または奥行きの単位位置)である。
//!
//! 横と縦は画面を等分した区画であり、焼く側はその中心の位置を使い、参照する側は画素の画面位置をそのまま渡す。
//! 横縦が画面に張り付いた量であって条件の表ではないため、この2軸には両端のテクセル中心を0と1に置く目盛り
//! (`unit_texel`)を使わない。使うと画面の端の半テクセルぶんがボリュームの外へ出る。奥行きだけはその目盛りを
//! 採る。先頭と末尾のスライスが距離0と最遠距離という条件そのものを表すため、両端の条件を補間で覆う必要がある。
//!
//! 奥行きは距離を線形に刻み、先頭のスライスを距離0に置く。距離0のスライスは散乱0・透過率1という厳密な値を持ち、
//! カメラの至近にある面が霞まないことを型でなく値で保証する。線形に刻むのは、この距離帯の光学的深さが1よりずっと
//! 小さく、散乱と透過率がどちらも距離のほぼ線形な関数だからである。指数刻みは遠方を粗くする代わりに近傍を細かく
//! するが、近傍こそ関数が最も直線に近い区間であり細かくする意味が無い。
//! 参照: Sebastien Hillaire, "A Scalable and Production Ready Sky and Atmosphere Rendering Technique" (EGSR 2020)の
//! `AerialPerspectiveSliceToDepth`(1スライスあたり固定のキロメートル数、すなわち距離の線形刻み)。
//! 最遠距離を出典の固定値でなくカメラの遠クリップ面に取るのは、この世界の見えるジオメトリが遠クリップ面の内側に
//! 収まっており、固定の数キロメートル刻みでは全ジオメトリが先頭の1スライスへ入ってしまうためである。
//!
//! 注意: この写像は`shaders/atmosphere_aerial_mapping.slang`の写しを持つ。ここが正本である。

use crate::atmosphere::mapping::unit_texel;

/// 奥行きの単位位置からカメラからの距離を求める。単位位置0が距離0、1が最遠距離である。
pub fn 空中遠近ボリュームの距離を求める(最遠距離: f64, 奥行き位置: f64) -> f64 {
    最遠距離 * 奥行き位置
}

/// カメラからの距離から奥行きの単位位置を求める。`空中遠近ボリュームの距離を求める`の逆写像である。
/// 最遠距離より遠い距離を1へ張り付けるのは、そこにある面へ最遠のスライスの霞をそのまま掛けるためである。
/// 最遠距離が0以下になるのは条件の生成が禁じているため、この除算は0除算にならない。
pub fn 空中遠近ボリュームの奥行き位置を求める(最遠距離: f64, 距離: f64) -> f64 {
    if 最遠距離 <= 0.0 {
        return 0.0;
    }
    (距離 / 最遠距離).clamp(0.0, 1.0)
}

/// ボクセルの横縦の添字から、そのボクセルが受け持つ画面の区画の中心の位置を求める。
/// 一辺が2以上であることは大気のベイク済み画像の解像度の生成が保証するため、この除算は0除算にならない。
pub fn 空中遠近ボリュームの画面位置を求める(横: u32, 縦: u32, 一辺: u32) -> [f64; 2] {
    [区画の中心(横, 一辺), 区画の中心(縦, 一辺)]
}

/// 奥行きのボクセルの添字から、そのボクセルが表す奥行きの単位位置を求める。
/// 両端の添字がちょうど0と1に対応するため、先頭のスライスが距離0、末尾のスライスが最遠距離になる。
pub fn 空中遠近ボリュームの奥行き添字の位置(奥: u32, 一辺: u32) -> f64 {
    f64::from(奥) / f64::from(一辺 - 1)
}

/// 参照する側がボリュームを標本する3成分の座標。横縦は画面の位置をそのまま渡し、奥行きは単位位置をテクセル中心のUVへ直す。
///
/// 横縦が素通りなのは、焼く側が区画の中心を標本点に取るため、画面の位置がそのままテクセル中心のUVになるからである。
/// 奥行きだけ直すのは、先頭と末尾のスライスが距離0と最遠距離という条件を表しており、その両端を補間で覆うためである。
pub fn 空中遠近ボリュームの標本座標を求める(画面位置: [f64; 2], 奥行き位置: f64, 一辺: u32) -> [f64; 3] {
    [画面位置[0], 画面位置[1], unit_texel::単位位置からテクセル中心のuv(奥行き位置, 一辺)]
}

fn 区画の中心(添字: u32, 一辺: u32) -> f64 {
    (f64::from(添字) + 0.5) / f64::from(一辺)
}
