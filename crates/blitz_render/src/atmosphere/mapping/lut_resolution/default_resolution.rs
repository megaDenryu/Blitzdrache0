//! 既定として採る解像度の値と、その出どころを所有するモジュール。
//! 担当するのは「どの解像度を既定にするか」という品質方針の選択であり、解像度という型の構造は親が持つ。
//!
//! 値を型の定義と同じ場所へ置かないのは、この6つが文献から採った選択であって型の不変条件ではないためである。
//! 出典を差し替えるとき直すのはこのファイルだけであり、型の側は動かない。
//! 参照: Sebastien Hillaire, "A Scalable and Production Ready Sky and Atmosphere Rendering Technique" (EGSR 2020)の実装の解像度。

use super::大気のベイク済み画像の解像度;

const 既定の透過率の幅: u32 = 256;
const 既定の透過率の高さ: u32 = 64;
const 既定の多重散乱の一辺: u32 = 32;
const 既定のスカイビューの幅: u32 = 192;
const 既定のスカイビューの高さ: u32 = 108;
const 既定の空中遠近の一辺: u32 = 32;

/// 検証を通さず組み立てるのは、6つの定数がどれも辺の長さの下限を満たすことがこのファイルで見て取れるためである。
pub(super) fn 既定値() -> 大気のベイク済み画像の解像度 {
    大気のベイク済み画像の解像度 {
        透過率の幅: 既定の透過率の幅,
        透過率の高さ: 既定の透過率の高さ,
        多重散乱の一辺: 既定の多重散乱の一辺,
        スカイビューの幅: 既定のスカイビューの幅,
        スカイビューの高さ: 既定のスカイビューの高さ,
        空中遠近の一辺: 既定の空中遠近の一辺,
    }
}
