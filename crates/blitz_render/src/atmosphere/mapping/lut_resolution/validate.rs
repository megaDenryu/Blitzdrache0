//! 解像度の各辺が写像の刻みを定義できる長さを持つかを確かめる工程。
//! 受け取るのは項目名と辺の長さの対の並び、返すのは最初に見つかった破れの型付きエラーである。
//!
//! 下限を2に置くのは、多重散乱LUT・スカイビューLUT・空中遠近ボリュームの写像が辺の長さから1を引いた値で割るため、
//! 1では刻みが定義できないからである。

use crate::atmosphere::大気数学エラー;

/// 写像が刻みを定義できる辺の長さの下限。
const 辺の長さの下限: u32 = 2;

pub(super) fn 辺の長さを確かめる(項目と値: &[(&'static str, u32)]) -> Result<(), 大気数学エラー> {
    for (項目, 値) in 項目と値 {
        if *値 < 辺の長さの下限 {
            return Err(大気数学エラー::整数値域外(項目, *値));
        }
    }
    Ok(())
}
