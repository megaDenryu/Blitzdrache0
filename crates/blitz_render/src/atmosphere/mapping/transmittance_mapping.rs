//! 透過率のベイク済み画像のテクセル座標と、観測点の半径・視線の天頂余弦との行き来を担う工程。
//! 受け取るのはテクセル座標(または半径と天頂余弦)、返すのは対応する視線(またはテクセル座標)である。
//!
//! 天頂余弦をそのまま軸に取らず、大気上端までの距離を「観測点の高さで到達しうる最短と最長の間のどこか」として
//! 軸に取る。地平線をかすめる視線の付近で光学距離が急に伸びるため、天頂余弦を等間隔に刻むとそこだけ標本が粗くなる。
//! 参照: Sebastien Hillaire, "A Scalable and Production Ready Sky and Atmosphere Rendering Technique" (EGSR 2020)の
//! `UvToLutTransmittanceParams`および`LutTransmittanceParamsToUv`。
//!
//! 注意: この写像は`shaders/atmosphere_mapping.slang`の写しを持つ。ここが正本であり、ずれるとベイク済み画像を焼いた座標と
//! 参照する座標が食い違って空の色が静かにずれる。一致はGPU読み戻し検査が代表テクセルで確かめる。

use crate::atmosphere::geometry::intersect::上端までの距離の生値;
use crate::atmosphere::narrowing;
use crate::atmosphere::{大気内観測点, 大気数学エラー, 天頂余弦, 消散媒体};

/// ベイク済み画像の1テクセルが表す視線。観測点は媒体を借りて大気の内側にあることを検証済みである。
#[derive(Debug, Clone, Copy)]
pub struct 透過率のベイク済み画像の視線<'媒体> {
    pub 観測点: 大気内観測点<'媒体>,
    pub 天頂余弦: 天頂余弦,
}

/// テクセル中心のUVから視線を求める。UVの縦が観測点の高さ、横が大気上端までの距離の位置である。
pub fn 透過率のベイク済み画像の視線を求める(
    媒体: &消散媒体,
    横uv: f32,
    縦uv: f32,
) -> Result<透過率のベイク済み画像の視線<'_>, 大気数学エラー> {
    let (下端, 上端) = 半径の生値(媒体);
    let 地平線までの距離 = (上端 * 上端 - 下端 * 下端).max(0.0).sqrt();
    let 地表からの弦 = 地平線までの距離 * f64::from(縦uv);
    let 半径 = (地表からの弦 * 地表からの弦 + 下端 * 下端).sqrt().clamp(下端, 上端);
    let 最短 = 上端 - 半径;
    let 最長 = 地表からの弦 + 地平線までの距離;
    let 距離 = 最短 + f64::from(横uv) * (最長 - 最短);
    let 余弦 = if 距離 <= 0.0 {
        1.0
    } else {
        ((地平線までの距離 * 地平線までの距離 - 地表からの弦 * 地表からの弦 - 距離 * 距離) / (2.0 * 半径 * 距離)).clamp(-1.0, 1.0)
    };
    Ok(透過率のベイク済み画像の視線 {
        観測点: 大気内観測点::生成する(媒体, narrowing::長さへ狭める(半径))?,
        天頂余弦: 天頂余弦::生成する(narrowing::実数へ狭める(余弦))?,
    })
}

/// 視線からテクセル中心のUVを求める。`透過率のベイク済み画像の視線を求める`の逆写像である。
pub fn 透過率のベイク済み画像のuvを求める(観測点: 大気内観測点<'_>, 天頂余弦: 天頂余弦) -> [f32; 2] {
    let (下端, 上端) = 半径の生値(観測点.媒体());
    let 生値 = 透過率のベイク済み画像のuvの生値(下端, 上端, f64::from(観測点.半径().値()), f64::from(天頂余弦.値()));
    [narrowing::実数へ狭める(生値[0]), narrowing::実数へ狭める(生値[1])]
}

/// 単位型を経由せず生値で同じ逆写像を求める入口。多重散乱の積分が経路の標本点ごとに呼ぶため、
/// 大気内観測点の生成と検証を通さずに済ませる。
pub(in crate::atmosphere) fn 透過率のベイク済み画像のuvの生値(下端: f64, 上端: f64, 半径: f64, 天頂余弦: f64) -> [f64; 2] {
    let 地平線までの距離 = (上端 * 上端 - 下端 * 下端).max(0.0).sqrt();
    let 地表からの弦 = (半径 * 半径 - 下端 * 下端).max(0.0).sqrt();
    let 距離 = 上端までの距離の生値(上端, 半径, 天頂余弦);
    let 最短 = 上端 - 半径;
    let 最長 = 地表からの弦 + 地平線までの距離;
    let 横 = if 最長 <= 最短 { 0.0 } else { (距離 - 最短) / (最長 - 最短) };
    let 縦 = if 地平線までの距離 <= 0.0 {
        0.0
    } else {
        地表からの弦 / 地平線までの距離
    };
    [横, 縦]
}

/// テクセルの添字から、そのテクセルの中心のUVを求める。書き込み側も読み出し側も中心を標本点にする。
pub fn テクセル中心のuv(添字: u32, 辺の長さ: u32) -> f32 {
    narrowing::実数へ狭める((f64::from(添字) + 0.5) / f64::from(辺の長さ))
}

fn 半径の生値(媒体: &消散媒体) -> (f64, f64) {
    (f64::from(媒体.下端半径().値()), f64::from(媒体.上端半径().値()))
}
