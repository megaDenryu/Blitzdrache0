//! プリコンピュートのベイク済み画像を何テクセルで焼くかの品質方針。
//! 既定の値とその出どころは`default_resolution`が、辺の長さの検証は`validate`が持つ。

mod accessors;
mod default_resolution;
mod validate;

use crate::atmosphere::大気数学エラー;

/// 各ベイク済み画像のテクセル数。資源の確保・計算の発行の計算の班数・テクセル座標の写像がすべてこの1つの値を読むため、
/// シェーダー側に解像度の定数を持たせない(シェーダーは書き込み先の寸法を実行時に問い合わせる)。
/// 不変条件: どの辺も2以上である(根拠は`validate`にある)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 大気のベイク済み画像の解像度 {
    透過率の幅: u32,
    透過率の高さ: u32,
    多重散乱の一辺: u32,
    スカイビューの幅: u32,
    スカイビューの高さ: u32,
    空中遠近の幅: u32,
    空中遠近の高さ: u32,
    空中遠近の奥行き: u32,
}

impl 大気のベイク済み画像の解像度 {
    pub fn 生成する(
        透過率の幅: u32,
        透過率の高さ: u32,
        多重散乱の一辺: u32,
        スカイビューの幅: u32,
        スカイビューの高さ: u32,
        空中遠近の寸法: [u32; 3],
    ) -> Result<Self, 大気数学エラー> {
        let [空中遠近の幅, 空中遠近の高さ, 空中遠近の奥行き] = 空中遠近の寸法;
        validate::辺の長さを確かめる(&[
            ("透過率のベイク済み画像の幅", 透過率の幅),
            ("透過率のベイク済み画像の高さ", 透過率の高さ),
            ("多重散乱のベイク済み画像の一辺", 多重散乱の一辺),
            ("スカイビューのベイク済み画像の幅", スカイビューの幅),
            ("スカイビューのベイク済み画像の高さ", スカイビューの高さ),
            ("空中遠近ボリュームの幅", 空中遠近の幅),
            ("空中遠近ボリュームの高さ", 空中遠近の高さ),
            ("空中遠近ボリュームの奥行き", 空中遠近の奥行き),
        ])?;
        Ok(Self {
            透過率の幅,
            透過率の高さ,
            多重散乱の一辺,
            スカイビューの幅,
            スカイビューの高さ,
            空中遠近の幅,
            空中遠近の高さ,
            空中遠近の奥行き,
        })
    }

    pub fn 既定値() -> Self {
        default_resolution::既定値()
    }
}
