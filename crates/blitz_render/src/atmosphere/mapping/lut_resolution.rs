//! プリコンピュートのベイク済み画像を何テクセルで焼くかの品質方針。
//! 既定の値とその出どころは`default_resolution`が、辺の長さの検証は`validate`が持つ。

mod default_resolution;
mod validate;

use crate::atmosphere::大気数学エラー;

/// 各ベイク済み画像のテクセル数。資源の確保・ディスパッチのワークグループ数・テクセル座標の写像がすべてこの1つの値を読むため、
/// シェーダー側に解像度の定数を持たせない(シェーダーは書き込み先の寸法を実行時に問い合わせる)。
/// 不変条件: どの辺も2以上である(根拠は`validate`にある)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 大気のベイク済み画像の解像度 {
    透過率の幅: u32,
    透過率の高さ: u32,
    多重散乱の一辺: u32,
    スカイビューの幅: u32,
    スカイビューの高さ: u32,
    空中遠近の一辺: u32,
}

impl 大気のベイク済み画像の解像度 {
    pub fn 生成する(
        透過率の幅: u32,
        透過率の高さ: u32,
        多重散乱の一辺: u32,
        スカイビューの幅: u32,
        スカイビューの高さ: u32,
        空中遠近の一辺: u32,
    ) -> Result<Self, 大気数学エラー> {
        validate::辺の長さを確かめる(&[
            ("透過率のベイク済み画像の幅", 透過率の幅),
            ("透過率のベイク済み画像の高さ", 透過率の高さ),
            ("多重散乱のベイク済み画像の一辺", 多重散乱の一辺),
            ("スカイビューのベイク済み画像の幅", スカイビューの幅),
            ("スカイビューのベイク済み画像の高さ", スカイビューの高さ),
            ("空中遠近ボリュームの一辺", 空中遠近の一辺),
        ])?;
        Ok(Self {
            透過率の幅,
            透過率の高さ,
            多重散乱の一辺,
            スカイビューの幅,
            スカイビューの高さ,
            空中遠近の一辺,
        })
    }

    pub fn 既定値() -> Self {
        default_resolution::既定値()
    }

    pub fn 透過率の幅(&self) -> u32 {
        self.透過率の幅
    }

    pub fn 透過率の高さ(&self) -> u32 {
        self.透過率の高さ
    }

    pub fn 多重散乱の一辺(&self) -> u32 {
        self.多重散乱の一辺
    }

    pub fn スカイビューの幅(&self) -> u32 {
        self.スカイビューの幅
    }

    pub fn スカイビューの高さ(&self) -> u32 {
        self.スカイビューの高さ
    }

    pub fn 空中遠近の一辺(&self) -> u32 {
        self.空中遠近の一辺
    }

    pub fn 透過率のテクセル数(&self) -> usize {
        要素数(&[self.透過率の幅, self.透過率の高さ])
    }

    pub fn 多重散乱のテクセル数(&self) -> usize {
        要素数(&[self.多重散乱の一辺, self.多重散乱の一辺])
    }

    pub fn スカイビューのテクセル数(&self) -> usize {
        要素数(&[self.スカイビューの幅, self.スカイビューの高さ])
    }

    pub fn 空中遠近のボクセル数(&self) -> usize {
        要素数(&[self.空中遠近の一辺; 3])
    }
}

fn 要素数(辺一覧: &[u32]) -> usize {
    辺一覧.iter().fold(1_usize, |積, 辺| {
        let 長さ = usize::try_from(*辺).unwrap_or_else(|_| panic!("ベイク済み画像の辺の長さ{辺}がusizeに収まらない"));
        積 * 長さ
    })
}
