//! 多重散乱LUTのテクセル座標と、観測点の高さ・太陽の向きとの対応。
//!
//! 透過率LUTと違って軸に細工をしないのは、多重散乱が向きにほとんど依存しない滑らかな量であり、
//! 地平線付近に標本を寄せる必要が無いためである。テクセルの中心でなく端から端までを等間隔に割り当てるのは、
//! 引く側が高さと太陽角の全域を補間で覆えるようにするためである。
//! 参照: Sebastien Hillaire, "A Scalable and Production Ready Sky and Atmosphere Rendering Technique" (EGSR 2020)の
//! `NewMultiScattCS`のuv導出(`fromSubUvsToUnit`によりテクセル中心が0から1へ引き伸ばされる)。
//!
//! 注意: この写像は`shaders/atmosphere_multiscatter.slang`の写しを持つ。ここが正本である。

use blitz_math::メートル;

use crate::atmosphere::narrowing;
use crate::atmosphere::{大気LUT解像度, 大気数学エラー, 天頂余弦, 消散媒体};

/// 最下行の観測点を地表からどれだけ持ち上げるか、大気の厚みに対する割合で表した量。
/// 地表ちょうどに置くと、どの向きへ出しても足元の地面と距離0で交わり、経路長が0になって値が消える。
/// 最上行を大気上端からわずかに下げるのも同じ理由で、上端ちょうどの点は上向きの経路を持たない。
/// 参照: Sebastien Hillaire, "A Scalable and Production Ready Sky and Atmosphere Rendering Technique" (EGSR 2020)の
/// `PLANET_RADIUS_OFFSET`。同出典は大気の厚みの1パーセントと10メートルを使う。
const 最下行を地表から離す割合: f64 = 0.01;
const 最上行を上端から離すメートル: f64 = 10.0;

/// LUTの1テクセルが表す条件。太陽の向きと観測点の高さの組である。
#[derive(Debug, Clone, Copy)]
pub struct 多重散乱lutの条件 {
    pub 太陽天頂余弦: 天頂余弦,
    pub 半径: メートル,
}

/// テクセルの添字から、そのテクセルが表す太陽の向きと観測点の半径を求める。
pub fn 多重散乱lutの条件を求める(
    媒体: &消散媒体,
    解像度: 大気LUT解像度,
    横: u32,
    縦: u32,
) -> Result<多重散乱lutの条件, 大気数学エラー> {
    let 一辺 = 解像度.多重散乱の一辺();
    let 横位置 = 端から端への位置(横, 一辺);
    let 縦位置 = 端から端への位置(縦, 一辺);
    let 下端 = f64::from(媒体.下端半径().値());
    let 上端 = f64::from(媒体.上端半径().値());
    let 高さの割合 = (縦位置 + 最下行を地表から離す割合).min(1.0);
    let 半径 = (下端 + 高さの割合 * (上端 - 下端 - 最上行を上端から離すメートル)).clamp(下端, 上端);
    Ok(多重散乱lutの条件 {
        太陽天頂余弦: 天頂余弦::生成する(narrowing::実数へ狭める((横位置 * 2.0 - 1.0).clamp(-1.0, 1.0)))?,
        半径: narrowing::長さへ狭める(半径),
    })
}

/// 太陽の向きと観測点の半径から、LUTの0から1までの位置の組を求める。`多重散乱lutの条件を求める`の逆写像である。
/// スカイビューの積分が経路の標本点ごとにこの表を引くため、条件から位置へ戻す向きが要る。
/// 範囲の外は端へ張り付ける。大気の外の半径は視線の経路上に現れないが、丸めで境界をわずかに越えることがある。
pub fn 多重散乱lutの単位位置を求める(媒体: &消散媒体, 太陽天頂余弦: f64, 半径: f64) -> [f64; 2] {
    let 下端 = f64::from(媒体.下端半径().値());
    let 上端 = f64::from(媒体.上端半径().値());
    let 横位置 = (太陽天頂余弦 * 0.5 + 0.5).clamp(0.0, 1.0);
    let 有効な厚み = 上端 - 下端 - 最上行を上端から離すメートル;
    let 縦位置 = if 有効な厚み <= 0.0 {
        0.0
    } else {
        ((半径 - 下端) / 有効な厚み - 最下行を地表から離す割合).clamp(0.0, 1.0)
    };
    [横位置, 縦位置]
}

/// テクセルの添字を0から1までの位置へ写す。両端のテクセルがちょうど0と1に対応する。
/// 一辺が2以上であることは大気LUT解像度の生成が保証するため、ここでの除算は0除算にならない。
fn 端から端への位置(添字: u32, 一辺: u32) -> f64 {
    f64::from(添字) / f64::from(一辺 - 1)
}
