//! スカイビューのベイク済み画像を参照する側の写像。担当する工程は「天頂を+Yに取ったワールドの視線と太陽方向から、
//! ベイク済み画像の縦横が意味する視線(天頂余弦と太陽方位余弦)を求める」ことである。受け取るのは単位ベクトル2本、
//! 返すのはベイク済み画像の1テクセルが表す視線である。
//!
//! 焼く側(`skyview_lut.rs`)が視線を作る向きと逆であり、これが空パスの入口に当たる。方位余弦を内積そのものでなく
//! 水平面へ落としてから取るのは、ベイク済み画像の横軸が「太陽との相対方位」であって「太陽との角度」ではないためである。
//! 両者を取り違えると、天頂付近の空が太陽との角度で暗くなるという静かな誤りになる。
//!
//! 注意: この写像は`shaders/sky_atmosphere_lookup.slang`の`skyViewRayOfWorldDirection`の写しを持つ。ここが正本である。

use super::skyview_mapping::スカイビューのベイク済み画像の視線;
use crate::atmosphere::geometry::vector3::{内積, 単位化, 長さ};
use crate::atmosphere::{大気数学エラー, 天頂余弦, 方位余弦};

/// 水平成分がこの長さ未満なら方位を決められないとみなす。天頂または天底を向く視線と、天頂にある太陽が対象である。
/// ベイク済み画像の縦0(天頂)と縦1(天底)の行はどの横位置でも同じ値であり、天頂の太陽はどの方位から見ても対称であるため、
/// この場合にどの方位を選んでも参照する値は変わらない。
///
/// 測るのはユークリッドの長さである。成分の絶対値の和ではないのは、この判定の直後に呼ぶ単位化が
/// ユークリッドの長さで割るため、割り算が安全である根拠を同じノルムで置く必要があるからである。
/// 和で測ると、和が下限を超えるのに長さが下限を割る向きを「方位を決められる」と扱ってしまう。
/// slang写しも`length`で測るため、2つのノルムを混ぜると同じ向きで答えが分かれる。
const 方位を決められない水平成分の長さ: f64 = 1.0e-6;

/// ワールドの視線と太陽方向からベイク済み画像の視線を求める。どちらも単位ベクトルであり、Yが天頂である。
pub fn ワールドの視線からスカイビューのベイク済み画像の視線を求める(
    視線: [f64; 3],
    太陽方向: [f64; 3],
) -> Result<スカイビューのベイク済み画像の視線, 大気数学エラー> {
    let 天頂余弦の値 = 視線[1].clamp(-1.0, 1.0);
    let 方位余弦の値 = 太陽との方位余弦を求める(視線, 太陽方向);
    Ok(スカイビューのベイク済み画像の視線 {
        視線天頂余弦: 天頂余弦::生成する(crate::atmosphere::narrowing::実数へ狭める(天頂余弦の値))?,
        太陽方位余弦: 方位余弦::生成する(crate::atmosphere::narrowing::実数へ狭める(方位余弦の値))?,
    })
}

/// 視線と太陽をそれぞれ水平面へ落とし、その2つのなす角の余弦を取る。
/// どちらかが水平成分を持たないときは1(太陽と同じ方位)を返す。その場合に参照するベイク済み画像の値が方位で変わらないためである。
fn 太陽との方位余弦を求める(視線: [f64; 3], 太陽方向: [f64; 3]) -> f64 {
    let (Some(視線の水平), Some(太陽の水平)) = (水平成分の向き(視線), 水平成分の向き(太陽方向)) else {
        return 1.0;
    };
    内積(視線の水平, 太陽の水平).clamp(-1.0, 1.0)
}

/// 天頂成分を落とした向き。長さが下限未満なら向きを持たないことを`None`で表す。
fn 水平成分の向き(向き: [f64; 3]) -> Option<[f64; 3]> {
    let 水平 = [向き[0], 0.0, 向き[2]];
    if 長さ(水平) < 方位を決められない水平成分の長さ {
        return None;
    }
    単位化(水平)
}
