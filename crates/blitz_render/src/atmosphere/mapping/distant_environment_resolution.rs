//! 遠方環境の立方体画像を何テクセルで焼くかの品質方針。
//!
//! 大気のベイク済み画像の解像度と同じ型へ入れないのは、遠方環境が大気の表ではなく、その上に置いた供給から作る
//! 間接照明の表現だからである。1つの型へ混ぜると、大気の表だけを焼き直すか遠方環境も焼き直すかという別の判断が
//! 同じ解像度の値に引きずられる。
//!
//! 既定の128は、元のスカイビュー(横192・縦108)の情報量と毎フレームの更新費の釣り合いによる
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「遠方環境の形式と生成(3-Ia)」)。

use crate::atmosphere::大気数学エラー;

/// 立方体の面の数。立方体である以上この値は6で固定であり、方針として選べる量ではない。
pub const 立方体の面数: u32 = 6;

/// 遠方環境の立方体画像1面の一辺のテクセル数。
/// 不変条件: 一辺は2以上である(1テクセルの面は面内位置の補間ができない)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 遠方環境の解像度 {
    面の一辺: u32,
}

impl 遠方環境の解像度 {
    pub fn 生成する(面の一辺: u32) -> Result<Self, 大気数学エラー> {
        if 面の一辺 < 2 {
            return Err(大気数学エラー::整数値域外("遠方環境の面の一辺", 面の一辺));
        }
        Ok(Self { 面の一辺 })
    }

    pub fn 既定値() -> Self {
        Self { 面の一辺: 128 }
    }

    pub fn 面の一辺(&self) -> u32 {
        self.面の一辺
    }

    pub fn 面のテクセル数(&self) -> usize {
        let 一辺 = usize::try_from(self.面の一辺).unwrap_or_else(|_| panic!("遠方環境の一辺{}がusizeに収まらない", self.面の一辺));
        一辺 * 一辺
    }

    /// 6面ぶんの合計。読み戻しの受け皿の容量と、焼いた期待値の並びの長さがこの値である。
    pub fn 全テクセル数(&self) -> usize {
        let 面数 = usize::try_from(立方体の面数).unwrap_or_else(|_| panic!("立方体の面数{立方体の面数}がusizeに収まらない"));
        self.面のテクセル数() * 面数
    }
}
