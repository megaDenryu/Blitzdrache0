//! テクセルの添字と「両端のテクセルが0と1に対応する単位位置」との行き来。
//! 受け取るのは添字または単位位置と辺の長さ、返すのは対応する単位位置またはテクセル中心のUVである。
//!
//! 多重散乱LUTとスカイビューLUTがこの目盛りを採るのは、引く側が条件の全域を補間で覆えるようにするためである。
//! テクセル中心をそのまま0と1に置くと、両端の半テクセルぶんが補間の外に落ちて端の条件を引けない。
//!
//! 注意: 2つの関数は互いの逆であり、往復が恒等であることを`atmosphere_tests`が検査する。
//! 注意: この写像は`shaders/atmosphere_skyview_mapping.slang`の`endToEndUnitPosition`と`texelCenterUvFromUnit`の
//! 写しを持つ。ここが正本である。

use crate::atmosphere::narrowing;

/// テクセルの添字を0から1までの単位位置へ写す。焼く側が使う。
/// 辺の長さが2以上であることは大気LUT解像度の生成が保証するため、ここでの除算は0除算にならない。
pub fn 端から端への単位位置(添字: u32, 辺の長さ: u32) -> f32 {
    narrowing::実数へ狭める(f64::from(添字) / f64::from(辺の長さ - 1))
}

/// 単位位置を、その位置に対応するテクセル中心のUVへ写す。引く側が使う。
/// 単位位置0が先頭テクセルの中心、1が末尾テクセルの中心を指すUVになる。
pub fn 単位位置からテクセル中心のuv(単位位置: f64, 辺の長さ: u32) -> f64 {
    (単位位置 * f64::from(辺の長さ - 1) + 0.5) / f64::from(辺の長さ)
}
