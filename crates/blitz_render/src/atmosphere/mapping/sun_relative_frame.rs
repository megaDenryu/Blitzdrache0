//! 太陽相対座標のフレームを組み、ワールドの向きとの行き来を担う工程。受け取るのは太陽方向とワールドの向き、
//! 返すのは太陽相対座標の向き(またはその逆)である。
//!
//! 遠方環境をワールド軸でなく太陽相対座標で焼くのは、鍵に太陽の方位を入れずに済ませるためである。
//! ワールド軸で焼くと同じ高度で方位だけ動く太陽が別の絵を作るため、太陽方向3成分を鍵へ入れることになる。
//! 太陽相対座標では方位の回転が座標系ごと回るため、焼いた内容が方位に依らない。
//!
//! 第一軸は太陽の水平成分の向き、第二軸は天頂(+Y)、第三軸は第一軸と第二軸の外積である。
//! この組み方でワールドの向きを写すと、写した向きと太陽相対の太陽(第三軸成分が0)から求めたスカイビューの視線が、
//! ワールドのまま求めた視線と一致する。
//!
//! 注意: この写像は`shaders/sun_relative_frame.slang`の写しを持つ。ここが正本である。

use crate::atmosphere::geometry::vector3::{内積, 単位化, 長さ};
use crate::atmosphere::mapping::skyview_lookup::方位を決められない水平成分の長さ;

/// 太陽の水平成分が失われたときに第一軸へ据える固定の向き。天頂または天底にある太陽はどの方位から見ても対称であり、
/// このとき参照するスカイビューの値は方位に依らないため、どの向きを選んでも焼いた内容は変わらない。
const 方位を決められないときの第一軸: [f64; 3] = [1.0, 0.0, 0.0];

/// 太陽を基準に組んだ正規直交フレーム。3本の軸はどれもワールドの単位ベクトルである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 太陽相対フレーム {
    第一軸: [f64; 3],
    第二軸: [f64; 3],
    第三軸: [f64; 3],
}

impl 太陽相対フレーム {
    /// 太陽方向からフレームを組む。太陽方向は単位ベクトルであり、天頂が+Yである。
    pub fn 太陽方向から組む(太陽方向: [f64; 3]) -> Self {
        let 水平 = [太陽方向[0], 0.0, 太陽方向[2]];
        let 第一軸 = if 長さ(水平) < 方位を決められない水平成分の長さ {
            方位を決められないときの第一軸
        } else {
            単位化(水平).unwrap_or(方位を決められないときの第一軸)
        };
        let 第二軸 = [0.0, 1.0, 0.0];
        Self {
            第一軸,
            第二軸,
            第三軸: [-第一軸[2], 0.0, 第一軸[0]],
        }
    }

    /// ワールドの向きを太陽相対座標へ写す。3本の軸との内積を並べるだけである。
    pub fn ワールドの向きを写す(&self, 向き: [f64; 3]) -> [f64; 3] {
        [内積(向き, self.第一軸), 内積(向き, self.第二軸), 内積(向き, self.第三軸)]
    }

    /// 太陽相対座標の向きをワールドへ戻す。`ワールドの向きを写す`の逆写像である。
    pub fn ワールドの向きへ戻す(&self, 太陽相対の向き: [f64; 3]) -> [f64; 3] {
        let [第一, 第二, 第三] = 太陽相対の向き;
        [
            self.第一軸[0] * 第一 + self.第二軸[0] * 第二 + self.第三軸[0] * 第三,
            self.第一軸[1] * 第一 + self.第二軸[1] * 第二 + self.第三軸[1] * 第三,
            self.第一軸[2] * 第一 + self.第二軸[2] * 第二 + self.第三軸[2] * 第三,
        ]
    }
}

/// 太陽の天頂余弦から、太陽相対座標での太陽の向きを求める。第三軸の成分は定義から必ず0である。
/// 焼く側は太陽の方位を1つも知らずにこの向きだけで済む。
pub fn 太陽相対座標の太陽方向(太陽天頂余弦: f64) -> [f64; 3] {
    let 水平成分 = (1.0 - 太陽天頂余弦 * 太陽天頂余弦).max(0.0).sqrt();
    [水平成分, 太陽天頂余弦, 0.0]
}
