//! 天空放射輝度供給。担当する工程は「向きを受け取り、太陽円盤を除いた連続な天空放射輝度を返す」ことである。
//! 受け取るのはワールドまたは太陽相対座標の視線、返すのはシーン線形RGBの放射輝度である。
//!
//! 太陽円盤を含めないのは、円盤が直接光の経路として別に数えられるためである。含めると同じ光路を
//! 空背景の視覚項と方向光の直接光項で二重に計上する
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「大気のベイク済み画像・空・太陽との接続」)。
//! 夜間背景放射輝度は昼夜の切替なしに常時足す。これも連続な環境の一部である。
//!
//! 注意: この式は`shaders/sky_radiance_supply.slang`の`skyRadianceSupply`の写しを持つ。ここが正本である。

use super::radiance_scale::天空放射輝度の尺度;
use crate::atmosphere::mapping::skyview_lookup::ワールドの視線からスカイビューのベイク済み画像の視線を求める;
use crate::atmosphere::mapping::skyview_mapping::{
    スカイビューのベイク済み画像の単位位置を求める, スカイビューのベイク済み画像の視線
};
use crate::atmosphere::mapping::sun_relative_frame::太陽相対座標の太陽方向;
use crate::atmosphere::{スカイビュー表, スカイビュー観測条件, 大気散乱媒体, 大気数学エラー};

/// 焼き上げたスカイビューの表の上に置く、方向1本ぶんの天空放射輝度の問い合わせ口。
/// 表と媒体を借用で持つのは、この供給が表の寿命の内側でしか意味を持たず、表の写しを作る理由が無いためである。
pub struct 天空放射輝度供給<'a> {
    媒体: &'a 大気散乱媒体,
    スカイビュー表: &'a スカイビュー表,
    観測条件: スカイビュー観測条件,
    尺度: 天空放射輝度の尺度,
}

impl<'a> 天空放射輝度供給<'a> {
    pub fn 生成する(
        媒体: &'a 大気散乱媒体,
        スカイビュー表: &'a スカイビュー表,
        観測条件: スカイビュー観測条件,
        尺度: 天空放射輝度の尺度,
    ) -> Self {
        Self {
            媒体,
            スカイビュー表,
            観測条件,
            尺度,
        }
    }

    pub fn 尺度(&self) -> 天空放射輝度の尺度 {
        self.尺度
    }

    /// ワールドの視線が運ぶ天空放射輝度。太陽方向はワールドの単位ベクトルである。
    /// これが空背景パスの画素段と同じ経路であり、空代表画素の照合がこの答えを実機の絵と突き合わせる。
    pub fn ワールドの視線の放射輝度を求める(
        &self, 視線: [f64; 3], 太陽方向: [f64; 3]
    ) -> Result<[f64; 3], 大気数学エラー> {
        let 視線 = ワールドの視線からスカイビューのベイク済み画像の視線を求める(視線, 太陽方向)?;
        Ok(self.視線の放射輝度を求める(視線))
    }

    /// 太陽相対座標の視線が運ぶ天空放射輝度。太陽の方位を1つも受け取らないのは、太陽相対座標では
    /// 太陽の水平成分が常に第一軸の正の側にあり、天頂余弦だけで太陽の向きが決まるためである。
    pub fn 太陽相対の視線の放射輝度を求める(&self, 太陽相対視線: [f64; 3]) -> Result<[f64; 3], 大気数学エラー> {
        let 太陽 = 太陽相対座標の太陽方向(f64::from(self.観測条件.太陽天頂余弦().値()));
        self.ワールドの視線の放射輝度を求める(太陽相対視線, 太陽)
    }

    /// スカイビューの視線から表を参照し、太陽の放射照度を掛けて夜間背景を足す。
    /// 0で下から切るのは、双一次補間と半精度の丸めが0の近くでわずかな負を作りうるためであり、
    /// 放射輝度が負になることに物理的な意味が無いからである。
    fn 視線の放射輝度を求める(&self, 視線: スカイビューのベイク済み画像の視線) -> [f64; 3] {
        let 観測半径 = f64::from(self.観測条件.観測半径(self.媒体.消散()).値());
        let [横位置, 縦位置] = スカイビューのベイク済み画像の単位位置を求める(self.媒体.消散(), 観測半径, 視線);
        let 標本 = self.スカイビュー表.単位位置から標本を参照する(横位置, 縦位置);
        let 太陽放射照度 = f64::from(self.尺度.太陽放射照度());
        let 夜空放射輝度 = self.尺度.夜空放射輝度();
        let mut 放射輝度 = [0.0_f64; 3];
        for 添字 in 0..3 {
            放射輝度[添字] = (標本[添字] * 太陽放射照度 + f64::from(夜空放射輝度[添字])).max(0.0);
        }
        放射輝度
    }
}
