//! 天空放射輝度供給が空の表へ掛ける尺度と、常時足す夜間の背景。
//!
//! 2つを1つの型で持つのは、どちらも「この世界の空をどう見せるか」の選択として空描画方針から同時に来るためであり、
//! 片方だけを差し替えた組を作る理由が無いからである。どちらも遠方環境キーの構成要素であるため、
//! 一方を鍵へ入れ忘れる欠陥もこの束ね方が防ぐ。

use crate::atmosphere::大気数学エラー;

/// 太陽の放射照度の尺度と夜間背景放射輝度の組。
/// 不変条件: 太陽放射照度は有限かつ正、夜空放射輝度は3成分とも有限かつ0以上である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 天空放射輝度の尺度 {
    太陽放射照度: f32,
    夜空放射輝度: [f32; 3],
}

impl 天空放射輝度の尺度 {
    pub fn 生成する(太陽放射照度: f32, 夜空放射輝度: [f32; 3]) -> Result<Self, 大気数学エラー> {
        if !太陽放射照度.is_finite() || 太陽放射照度 <= 0.0 {
            return Err(大気数学エラー::値域外("天空放射輝度の太陽放射照度", 太陽放射照度));
        }
        for 値 in 夜空放射輝度 {
            if !値.is_finite() || 値 < 0.0 {
                return Err(大気数学エラー::値域外("天空放射輝度の夜空放射輝度", 値));
            }
        }
        Ok(Self {
            太陽放射照度, 夜空放射輝度
        })
    }

    pub fn 太陽放射照度(&self) -> f32 {
        self.太陽放射照度
    }

    pub fn 夜空放射輝度(&self) -> [f32; 3] {
        self.夜空放射輝度
    }
}
