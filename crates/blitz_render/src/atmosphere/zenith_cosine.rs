//! 視線と天頂方向のなす角の余弦。大気の数学が視線の向きを1つの数で表すときの型。

use super::大気数学エラー;

/// 観測点の天頂方向と視線方向の内積。1が真上、0が水平、-1が真下である。
/// 球対称の大気では、視線の向きのうち結果に効くのはこの1つの数だけである(方位角には依存しない)。
/// 不変条件: 有限かつ-1以上1以下である。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 天頂余弦(f32);

impl 天頂余弦 {
    pub fn 生成する(値: f32) -> Result<Self, 大気数学エラー> {
        if !値.is_finite() || !(-1.0..=1.0).contains(&値) {
            return Err(大気数学エラー::値域外("天頂余弦", 値));
        }
        Ok(Self(値))
    }

    /// 前提: 値は有限かつ-1以上1以下である。地平線の余弦のように、定義から値域が保証される導出だけがこの入口を使う。
    pub(super) fn 検証済みの値から(値: f32) -> Self {
        Self(値)
    }

    pub fn 値(&self) -> f32 {
        self.0
    }
}
