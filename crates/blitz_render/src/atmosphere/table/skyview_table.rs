//! CPU側に焼いたスカイビューのベイク済み画像と、そこからの双一次補間の標本取り。
//! 受け取るのはテクセル中心のUV、返すのはその位置の空の放射輝度(太陽の放射照度を1とした値)である。
//!
//! 空パスのGPUシェーダーが同じベイク済み画像をサンプラーで参照するため、`blitz_app`の空代表画素報告がこの表を通して
//! 実機画素と同じ補間を再現する。標本を参照する操作を透過率・多重散乱の表と違って公開するのは、
//! この表を参照する側がblitz_render内部の積分でなく、外部の空代表画素報告(CPU正本照合)だからである。

use super::bilinear;
use crate::atmosphere::mapping::unit_texel::単位位置からテクセル中心のuv;
use crate::atmosphere::{
    スカイビューのベイク済み画像を焼く, スカイビュー放射輝度RGB, スカイビュー観測条件, 多重散乱表, 大気のベイク済み画像の解像度, 大気散乱媒体,
    大気数学エラー, 透過率表,
};

pub struct スカイビュー表 {
    解像度: 大気のベイク済み画像の解像度,
    テクセル一覧: Vec<スカイビュー放射輝度RGB>,
}

impl スカイビュー表 {
    pub fn 焼く(
        媒体: &大気散乱媒体,
        透過率表: &透過率表,
        多重散乱表: &多重散乱表,
        解像度: 大気のベイク済み画像の解像度,
        観測条件: スカイビュー観測条件,
    ) -> Result<Self, 大気数学エラー> {
        Ok(Self {
            解像度,
            テクセル一覧: スカイビューのベイク済み画像を焼く(媒体, 透過率表, 多重散乱表, 解像度, 観測条件)?,
        })
    }

    pub fn テクセル一覧(&self) -> &[スカイビュー放射輝度RGB] {
        &self.テクセル一覧
    }

    /// 両端が0と1になる単位位置の放射輝度を求める。テクセル中心のUVへ直す変換をこの表の内側へ閉じるのは、
    /// 参照する側(空パスの写しとその外部照合)が解像度を知らなくても参照できるようにするためである。GPU側の
    /// `sampleSkyView`が単位位置からテクセル中心UVへ直したうえでサンプラーへ渡す並びと同じである。
    pub fn 単位位置から標本を参照する(&self, 横位置: f64, 縦位置: f64) -> [f64; 3] {
        let 横uv = 単位位置からテクセル中心のuv(横位置, self.解像度.スカイビューの幅());
        let 縦uv = 単位位置からテクセル中心のuv(縦位置, self.解像度.スカイビューの高さ());
        self.標本を参照する(横uv, 縦uv)
    }

    /// UVの位置の放射輝度を双一次補間で求める。GPU側のサンプラーと同じ規則(テクセル中心を標本点とし、
    /// 範囲の外は端のテクセルへ張り付ける)で参照する。
    pub fn 標本を参照する(&self, 横uv: f64, 縦uv: f64) -> [f64; 3] {
        let (左, 右, 横比) = bilinear::添字と比(横uv, self.解像度.スカイビューの幅());
        let (上, 下, 縦比) = bilinear::添字と比(縦uv, self.解像度.スカイビューの高さ());
        bilinear::混ぜる(
            self.テクセル(左, 上),
            self.テクセル(右, 上),
            self.テクセル(左, 下),
            self.テクセル(右, 下),
            横比,
            縦比,
        )
    }

    fn テクセル(&self, 横: u32, 縦: u32) -> [f64; 3] {
        let 幅 = usize::try_from(self.解像度.スカイビューの幅()).unwrap_or(0);
        let 横 = usize::try_from(横).unwrap_or(0);
        let 縦 = usize::try_from(縦).unwrap_or(0);
        let Some(値) = self.テクセル一覧.get(縦 * 幅 + 横) else {
            panic!("スカイビュー表の範囲外を参照した(横{横} 縦{縦})。添字の切り詰めが効いていない");
        };
        値.成分().map(f64::from)
    }
}
