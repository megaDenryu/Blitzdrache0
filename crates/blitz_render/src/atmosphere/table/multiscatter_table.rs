//! CPU側に焼いた多重散乱のベイク済み画像と、そこからの双一次補間の標本取り。
//! 受け取るのは太陽天頂余弦と観測点の半径、返すのはその条件の多重散乱である。
//!
//! スカイビューの積分がこの表を参照するのは、GPU側のスカイビューシェーダーが多重散乱のベイク済み画像をサンプラーで参照するからである。
//! 条件から参照する位置は`multiscatter_mapping`の逆写像が決め、単位位置からテクセル中心のUVへの直しは
//! `unit_texel`が持つ。両端のテクセルが単位位置の0と1に対応するため、この直しを省くと半テクセルぶんずれる。

use super::bilinear;
use crate::atmosphere::mapping::multiscatter_mapping::多重散乱のベイク済み画像の単位位置を求める;
use crate::atmosphere::mapping::unit_texel::単位位置からテクセル中心のuv;
use crate::atmosphere::{
    多重散乱RGB, 多重散乱のベイク済み画像を焼く, 大気のベイク済み画像の解像度, 大気散乱媒体, 大気数学エラー, 透過率表
};

pub struct 多重散乱表 {
    解像度: 大気のベイク済み画像の解像度,
    テクセル一覧: Vec<多重散乱RGB>,
}

impl 多重散乱表 {
    pub fn 焼く(
        媒体: &大気散乱媒体, 透過率表: &透過率表, 解像度: 大気のベイク済み画像の解像度
    ) -> Result<Self, 大気数学エラー> {
        Ok(Self {
            解像度,
            テクセル一覧: 多重散乱のベイク済み画像を焼く(媒体, 透過率表, 解像度)?,
        })
    }

    pub fn テクセル一覧(&self) -> &[多重散乱RGB] {
        &self.テクセル一覧
    }

    /// その条件の多重散乱を双一次補間で求める。計算はf64で行い、スカイビューの積分がそのまま使う。
    pub(in crate::atmosphere) fn 標本を参照する(&self, 媒体: &大気散乱媒体, 太陽天頂余弦: f64, 半径: f64) -> [f64; 3] {
        let 一辺 = self.解像度.多重散乱の一辺();
        let [横位置, 縦位置] = 多重散乱のベイク済み画像の単位位置を求める(媒体.消散(), 太陽天頂余弦, 半径);
        let (左, 右, 横比) = bilinear::添字と比(単位位置からテクセル中心のuv(横位置, 一辺), 一辺);
        let (上, 下, 縦比) = bilinear::添字と比(単位位置からテクセル中心のuv(縦位置, 一辺), 一辺);
        bilinear::混ぜる(
            self.テクセル(左, 上),
            self.テクセル(右, 上),
            self.テクセル(左, 下),
            self.テクセル(右, 下),
            横比,
            縦比,
        )
    }

    fn テクセル(&self, 横: u32, 縦: u32) -> [f64; 3] {
        let 一辺 = usize::try_from(self.解像度.多重散乱の一辺()).unwrap_or(0);
        let 横 = usize::try_from(横).unwrap_or(0);
        let 縦 = usize::try_from(縦).unwrap_or(0);
        let Some(値) = self.テクセル一覧.get(縦 * 一辺 + 横) else {
            panic!("多重散乱表の範囲外を参照した(横{横} 縦{縦})。添字の切り詰めが効いていない");
        };
        値.成分().map(f64::from)
    }
}
