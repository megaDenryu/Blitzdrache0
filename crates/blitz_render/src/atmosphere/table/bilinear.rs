//! テクセル中心を標本点とする双一次補間の、両隣の添字と混ぜ具合を求める工程。
//! 受け取るのはUVと辺の長さ、返すのは手前と奥の添字とその間の比である。
//!
//! CPU側の表がこの規則を持つのは、GPU側が同じベイク済み画像をサンプラーで参照するからである。CPUが解析的に値を求め直すと、
//! 補間の有無だけで両者がずれ、写しの誤りと区別できなくなる。規則はVulkanのLINEARフィルタと
//! CLAMP_TO_EDGEアドレスモードに合わせてある(範囲の外は端のテクセルへ張り付ける)。

use crate::floor_index::実数位置の床の添字;

/// UVから両隣の添字と混ぜ具合を求める。返す比は0以上1以下である。
pub(in crate::atmosphere) fn 添字と比(uv: f64, 辺の長さ: u32) -> (u32, u32, f64) {
    let 位置 = uv * f64::from(辺の長さ) - 0.5;
    let 最大添字 = 辺の長さ - 1;
    let 手前 = 実数位置の床の添字(位置, 最大添字);
    let 比 = (位置 - f64::from(手前)).clamp(0.0, 1.0);
    (手前, (手前 + 1).min(最大添字), 比)
}

/// 4隅の値を横比・縦比で混ぜる。成分数は3で固定であり、ベイク済み画像のRGBだけを扱う。
pub(in crate::atmosphere) fn 混ぜる(左上: [f64; 3], 右上: [f64; 3], 左下: [f64; 3], 右下: [f64; 3], 横比: f64, 縦比: f64) -> [f64; 3] {
    let mut 結果 = [0.0; 3];
    for 添字 in 0..3 {
        let 上辺 = 左上[添字] + (右上[添字] - 左上[添字]) * 横比;
        let 下辺 = 左下[添字] + (右下[添字] - 左下[添字]) * 横比;
        結果[添字] = 上辺 + (下辺 - 上辺) * 縦比;
    }
    結果
}
