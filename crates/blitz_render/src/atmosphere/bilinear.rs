//! テクセル中心を標本点とする双一次補間の、両隣の添字と混ぜ具合を求める工程。
//! 受け取るのはUVと辺の長さ、返すのは手前と奥の添字とその間の比である。
//!
//! CPU側の表がこの規則を持つのは、GPU側が同じLUTをサンプラーで引くからである。CPUが解析的に値を求め直すと、
//! 補間の有無だけで両者がずれ、写しの誤りと区別できなくなる。規則はVulkanのLINEARフィルタと
//! CLAMP_TO_EDGEアドレスモードに合わせてある(範囲の外は端のテクセルへ張り付ける)。

/// UVから両隣の添字と混ぜ具合を求める。返す比は0以上1以下である。
pub(super) fn 添字と比(uv: f64, 辺の長さ: u32) -> (u32, u32, f64) {
    let 位置 = uv * f64::from(辺の長さ) - 0.5;
    let 最大添字 = 辺の長さ - 1;
    let 手前 = 床の添字(位置, 最大添字);
    let 比 = (位置 - f64::from(手前)).clamp(0.0, 1.0);
    (手前, (手前 + 1).min(最大添字), 比)
}

/// 4隅の値を横比・縦比で混ぜる。成分数は3で固定であり、LUTのRGBだけを扱う。
pub(super) fn 混ぜる(左上: [f64; 3], 右上: [f64; 3], 左下: [f64; 3], 右下: [f64; 3], 横比: f64, 縦比: f64) -> [f64; 3] {
    let mut 結果 = [0.0; 3];
    for 添字 in 0..3 {
        let 上辺 = 左上[添字] + (右上[添字] - 左上[添字]) * 横比;
        let 下辺 = 左下[添字] + (右下[添字] - 左下[添字]) * 横比;
        結果[添字] = 上辺 + (下辺 - 上辺) * 縦比;
    }
    結果
}

/// 実数の位置以下で最大の添字を、範囲の外を端へ張り付けたうえで返す。
///
/// 二分探索で求めるのは、浮動小数から整数への安全な標準変換が無く(`as`キャストは規約で禁止)、
/// 既存の文字列往復による丸めはテクセルごとに何度も呼ぶこの経路には遅すぎるためである。
/// 辺の長さは256以下であり、比較は8回程度で終わる。
fn 床の添字(位置: f64, 最大添字: u32) -> u32 {
    if 位置.is_nan() || 位置 <= 0.0 {
        return 0;
    }
    if 位置 >= f64::from(最大添字) {
        return 最大添字;
    }
    let mut 下 = 0u32;
    let mut 上 = 最大添字;
    while 下 < 上 {
        let 中 = 下 + (上 - 下).div_ceil(2);
        if f64::from(中) <= 位置 {
            下 = 中;
        } else {
            上 = 中 - 1;
        }
    }
    下
}
