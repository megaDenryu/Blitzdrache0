//! 密度が最大の高度での値を1とした、高度ごとの相対的な密度。

use super::大気数学エラー;

/// 高度における成分の密度を、その成分の密度が最大になる高度での密度で割った無次元量。
/// 消散係数の表がこの規格化に合わせて「密度が最大の高度での係数」を載せているため、
/// 消散係数とこの密度の積がその高度での実効的な消散係数になる。
/// 不変条件: 有限かつ0以上1以下である。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 規格化密度(f32);

impl 規格化密度 {
    pub fn 生成する(値: f32) -> Result<Self, 大気数学エラー> {
        if !値.is_finite() || !(0.0..=1.0).contains(&値) {
            return Err(大気数学エラー::値域外("規格化密度", 値));
        }
        Ok(Self(値))
    }

    /// 前提: 値は0以上1以下へ切り詰め済みである。層の式を評価した直後の切り詰めだけがこの入口を使う。
    pub(super) fn 検証済みの値から(値: f32) -> Self {
        Self(値)
    }

    pub fn 値(&self) -> f32 {
        self.0
    }
}
