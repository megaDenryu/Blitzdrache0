//! f64で計算した量をf32へ狭める境界。受け取るのはf64の生値、返すのは単位付きのf32の値である。
//!
//! 大気の数学をf64で行うのは、惑星半径が6.36e6メートルという桁を持つ一方で、視線が地平線をかすめるときの
//! 交差距離の判別式が2つの大きな量の差になるためである。f32では有効数字7桁しかなく、この差で桁落ちが起きる。
//!
//! 標準ライブラリはf64からf32への型付き変換を持たず、数値の`as`キャストは規約で禁じているため、
//! glamのベクタ縮小を1成分に使う(`blitz_math`の大域秒が同じ手を採る)。
//!
//! 注意: 狭めた結果が有限の範囲に収まる根拠は、入力側の値オブジェクトが値域を検証していることにある。
//! 半径と光学距離は大気の厚みと惑星半径で上から押さえられ、規格化密度と透過率は0以上1以下である。
//! この根拠が成り立つことは、全出力の有限性を見る検査が反証可能な形で確かめる。

use glam::DVec3;

use blitz_math::メートル;

pub(super) fn 実数へ狭める(値: f64) -> f32 {
    DVec3::splat(値).as_vec3().x
}

pub(super) fn 長さへ狭める(値: f64) -> メートル {
    メートル::生成する(実数へ狭める(値))
}
