//! 空中遠近ボリュームを1つ焼く条件。観測点の高度・太陽の向き・カメラの視錐台の向き・最遠距離の4つである。

use blitz_math::メートル;

use crate::atmosphere::{単位方向, 大気数学エラー, 消散媒体, 視錐台の向き};

/// 空中遠近ボリュームの中身を決める、大気以外の4つの入力。
///
/// 観測高度をカメラの高度でなく世界の方針から取るのは、スカイビューのベイク済み画像と同じ理由である。放射輝度が高さで変わる尺度は
/// 空気分子の尺度高度8000メートルであり、カメラが数十メートル上下しても1パーセント程度しか動かない。方針値に留めることで
/// カメラの大域位置が1つも入らず、大域原点を動かしても値が変わらない(カメラ相対契約)。カメラから入るのは向きと射影だけである。
/// 太陽の放射照度を持たないのは、放射照度が線形に効くためベイク済み画像を1として焼き描画側が掛けるからである。
///
/// 不変条件: 観測高度は有限かつ0以上であり、最遠距離は有限かつ正である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 空中遠近観測条件 {
    観測高度: メートル,
    太陽方向: 単位方向,
    視錐台の向き: 視錐台の向き,
    最遠距離: メートル,
}

impl 空中遠近観測条件 {
    pub fn 生成する(
        観測高度: メートル,
        太陽方向: 単位方向,
        視錐台の向き: 視錐台の向き,
        最遠距離: メートル,
    ) -> Result<Self, 大気数学エラー> {
        if !観測高度.値().is_finite() || 観測高度.値() < 0.0 {
            return Err(大気数学エラー::値域外("空中遠近の観測高度", 観測高度.値()));
        }
        if !最遠距離.値().is_finite() || 最遠距離.値() <= 0.0 {
            return Err(大気数学エラー::値域外("空中遠近の最遠距離", 最遠距離.値()));
        }
        Ok(Self {
            観測高度,
            太陽方向,
            視錐台の向き,
            最遠距離,
        })
    }

    pub fn 観測高度(&self) -> メートル {
        self.観測高度
    }

    pub fn 太陽方向(&self) -> 単位方向 {
        self.太陽方向
    }

    pub fn 視錐台の向き(&self) -> 視錐台の向き {
        self.視錐台の向き
    }

    pub fn 最遠距離(&self) -> メートル {
        self.最遠距離
    }

    /// 惑星中心から測った観測点の距離。大気の外を指す高度は上端へ切り詰める(スカイビュー観測条件と同じ扱い)。
    pub fn 観測半径(&self, 媒体: &消散媒体) -> メートル {
        let 半径 = 媒体.下端半径() + self.観測高度;
        if 半径 > 媒体.上端半径() { 媒体.上端半径() } else { 半径 }
    }
}
