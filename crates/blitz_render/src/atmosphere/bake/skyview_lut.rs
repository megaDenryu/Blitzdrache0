//! スカイビューのベイク済み画像の1テクセルの値を求める工程。受け取るのは媒体・2つの表・観測条件・テクセルの添字、
//! 返すのはそのテクセルが表す視線の放射輝度である。
//!
//! これがベイク済み画像の内容の正本であり、`shaders/atmosphere_skyview.slang`と`shaders/atmosphere_skyview_geometry.slang`が
//! テクセル座標の解釈と幾何の組み立ての写しを持つ。
//!
//! 太陽の放射照度を掛けずに1として焼くのは、放射照度が線形に効く量であり、ベイク済み画像を太陽の明るさから独立に
//! 保てるためである。太陽が明るくなっただけで焼き直す必要が無く、更新の鍵も放射照度を持たなくてよい。
//! 参照: Sebastien Hillaire, "A Scalable and Production Ready Sky and Atmosphere Rendering Technique" (EGSR 2020)の
//! `SkyViewLutCS`と`RaymarchScattering`。

use crate::atmosphere::integration::skyview_march::視線を積分する;
use crate::atmosphere::integration::skyview_step::視線の幾何;
use crate::atmosphere::mapping::skyview_mapping::スカイビューのベイク済み画像の視線を求める;
use crate::atmosphere::mapping::unit_texel::端から端への単位位置;
use crate::atmosphere::table::multiscatter_table::多重散乱表;
use crate::atmosphere::{
    スカイビュー放射輝度RGB, スカイビュー観測条件, 大気のベイク済み画像の解像度, 大気散乱媒体, 大気数学エラー, 透過率表
};

pub fn スカイビューのベイク済み画像のテクセル値(
    媒体: &大気散乱媒体,
    透過率表: &透過率表,
    多重散乱表: &多重散乱表,
    解像度: 大気のベイク済み画像の解像度,
    条件: スカイビュー観測条件,
    横: u32,
    縦: u32,
) -> Result<スカイビュー放射輝度RGB, 大気数学エラー> {
    let 横位置 = f64::from(端から端への単位位置(横, 解像度.スカイビューの幅()));
    let 縦位置 = f64::from(端から端への単位位置(縦, 解像度.スカイビューの高さ()));
    let 観測半径 = f64::from(条件.観測半径(媒体.消散()).値());
    let 視線 = スカイビューのベイク済み画像の視線を求める(媒体.消散(), 観測半径, 横位置, 縦位置)?;
    let 幾何 = 幾何を組む(観測半径, f64::from(条件.太陽天頂余弦().値()), &視線);
    let 放射輝度 = 視線を積分する(媒体, 透過率表, 多重散乱表, &幾何)?;
    let 狭めた = 放射輝度.map(crate::atmosphere::narrowing::実数へ狭める);
    スカイビュー放射輝度RGB::生成する(狭めた[0], 狭めた[1], 狭めた[2])
}

/// ベイク済み画像全体を走査して各テクセルの放射輝度を求める。GPUが焼いた結果と突き合わせる期待値がこれである。
/// テクセルの並びは横方向が先で、GPUの画像を行優先で読み戻した並びと一致する。
pub fn スカイビューのベイク済み画像を焼く(
    媒体: &大気散乱媒体,
    透過率表: &透過率表,
    多重散乱表: &多重散乱表,
    解像度: 大気のベイク済み画像の解像度,
    条件: スカイビュー観測条件,
) -> Result<Vec<スカイビュー放射輝度RGB>, 大気数学エラー> {
    let mut 一覧 = Vec::with_capacity(解像度.スカイビューのテクセル数());
    for 縦 in 0..解像度.スカイビューの高さ() {
        for 横 in 0..解像度.スカイビューの幅() {
            一覧.push(スカイビューのベイク済み画像のテクセル値(
                媒体,
                透過率表,
                多重散乱表,
                解像度,
                条件,
                横,
                縦,
            )?);
        }
    }
    Ok(一覧)
}

/// 天頂を+Zに取り、太陽をXZ平面の正のX側へ置いた座標系を組む。
/// 太陽の方位を軸に固定できるのは、ベイク済み画像の横軸が太陽に対する相対方位だからである。視線のY成分を常に非負に取るのは、
/// 球対称の大気では太陽をまたぐ方位の符号が結果を変えないためである。
fn 幾何を組む(
    観測半径: f64,
    太陽天頂余弦: f64,
    視線: &crate::atmosphere::mapping::skyview_mapping::スカイビューのベイク済み画像の視線,
) -> 視線の幾何 {
    let 太陽横成分 = (1.0 - 太陽天頂余弦 * 太陽天頂余弦).max(0.0).sqrt();
    let 視線天頂余弦 = f64::from(視線.視線天頂余弦.値());
    let 視線横成分 = (1.0 - 視線天頂余弦 * 視線天頂余弦).max(0.0).sqrt();
    let 方位余弦 = f64::from(視線.太陽方位余弦.値());
    let 方位正弦 = (1.0 - 方位余弦 * 方位余弦).max(0.0).sqrt();
    視線の幾何 {
        観測位置: [0.0, 0.0, 観測半径],
        視線: [視線横成分 * 方位余弦, 視線横成分 * 方位正弦, 視線天頂余弦],
        太陽: [太陽横成分, 0.0, 太陽天頂余弦],
    }
}
