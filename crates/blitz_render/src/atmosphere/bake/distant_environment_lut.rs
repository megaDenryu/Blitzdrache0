//! 遠方環境の立方体画像の1テクセルの値を求める工程。受け取るのは天空放射輝度供給・解像度・面とテクセルの添字、
//! 返すのはそのテクセルが表す向きの天空放射輝度である。
//!
//! これが遠方環境の内容の正本であり、`shaders/distant_environment.slang`がテクセル座標の解釈と向きの組み立ての
//! 写しを持つ。焼くのは太陽相対座標であり、テクセルの向きはそのままスカイビューの視線として使える。
//!
//! 太陽の放射照度と夜間背景を掛けた後の値を保持するのは、この画像が間接照明の終端供給元であり、
//! 参照する側が尺度を知らずに読めることを契約にするためである(スカイビューの表とはここが違う)。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「遠方環境の形式と生成(3-Ia)」

use crate::atmosphere::mapping::cube_face::{立方体の全面, 立方体の面};
use crate::atmosphere::mapping::cube_face_mapping::{テクセル中心の面内位置, 面と面内位置から向きを求める};
use crate::atmosphere::mapping::distant_environment_resolution::遠方環境の解像度;
use crate::atmosphere::supply::sky_radiance::天空放射輝度供給;
use crate::atmosphere::{大気数学エラー, 天空放射輝度RGB};

/// 1テクセルの値。テクセル中心の向きを1本だけ標本する。立体角の平均を取らないのは、遠方環境が
/// 拡散・鏡面の畳み込みの入力であり、畳み込みの側が広い立体角で平均を取るためである。
pub fn 遠方環境のテクセル値(
    供給: &天空放射輝度供給<'_>,
    解像度: 遠方環境の解像度,
    面: 立方体の面,
    横: u32,
    縦: u32,
) -> Result<天空放射輝度RGB, 大気数学エラー> {
    let 一辺 = 解像度.面の一辺();
    let 向き = 面と面内位置から向きを求める(面, テクセル中心の面内位置(横, 一辺), テクセル中心の面内位置(縦, 一辺));
    let 放射輝度 = 供給.太陽相対の視線の放射輝度を求める(向き)?;
    let 狭めた = 放射輝度.map(crate::atmosphere::narrowing::実数へ狭める);
    天空放射輝度RGB::生成する(狭めた[0], 狭めた[1], 狭めた[2])
}

/// 6面すべてを走査して各テクセルの放射輝度を求める。GPUが焼いた結果と突き合わせる期待値がこれである。
/// 並びは面(層番号の順)が最も外、次に縦、横が最も速い。GPUの2次元配列画像を全層まとめて読み戻した並びと一致する。
pub fn 遠方環境を焼く(
    供給: &天空放射輝度供給<'_>, 解像度: 遠方環境の解像度
) -> Result<Vec<天空放射輝度RGB>, 大気数学エラー> {
    let mut 一覧 = Vec::with_capacity(解像度.全テクセル数());
    for 面 in 立方体の全面 {
        for 縦 in 0..解像度.面の一辺() {
            for 横 in 0..解像度.面の一辺() {
                一覧.push(遠方環境のテクセル値(供給, 解像度, 面, 横, 縦)?);
            }
        }
    }
    Ok(一覧)
}
