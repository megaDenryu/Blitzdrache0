//! 空中遠近ボリュームの1ボクセルの値を求める工程と、ボリューム全体の走査。
//! 受け取るのは媒体・2つの表・解像度・観測条件・ボクセルの添字、返すのはそのボクセルが表す散乱と代表透過率である。
//!
//! これがボリュームの内容の正本であり、`shaders/atmosphere_aerial.slang`がボクセル座標の解釈と積分の写しを持つ。
//!
//! 積分の区間長を解像度と最遠距離だけから決めるため、どのボクセルも同じ格子の上に載る。ボクセルの奥行きの添字が
//! そのまま積む区間の数になり、先頭のスライス(距離0)は区間数0で散乱0・透過率1になる。
//! 参照: Sebastien Hillaire, "A Scalable and Production Ready Sky and Atmosphere Rendering Technique" (EGSR 2020)の
//! `CameraVolumeRayMarchCS`。

use super::aerial_condition::空中遠近観測条件;
use crate::atmosphere::integration::aerial_march::{
    スライスあたりの標本区間数, 代表透過率へ丸める, 視線を区間数ぶん積む
};
use crate::atmosphere::integration::skyview_step::視線の幾何;
use crate::atmosphere::mapping::aerial_mapping::空中遠近ボリュームの画面位置を求める;
use crate::atmosphere::narrowing;
use crate::atmosphere::table::multiscatter_table::多重散乱表;
use crate::atmosphere::table::transmittance_table::透過率表;
use crate::atmosphere::{大気のベイク済み画像の解像度, 大気散乱媒体, 大気数学エラー, 空中遠近ボクセル値};

/// 1つのボリュームを焼くのに要る材料。引数の列が伸び続けるのを避けて1つに束ねる。
#[derive(Clone, Copy)]
pub struct 空中遠近ボリュームの材料<'a> {
    pub 媒体: &'a 大気散乱媒体,
    pub 透過率表: &'a 透過率表,
    pub 多重散乱表: &'a 多重散乱表,
    pub 解像度: 大気のベイク済み画像の解像度,
    pub 条件: 空中遠近観測条件,
}

pub fn 空中遠近ボリュームのボクセル値(
    材料: 空中遠近ボリュームの材料<'_>,
    横: u32,
    縦: u32,
    奥: u32,
) -> Result<空中遠近ボクセル値, 大気数学エラー> {
    let [横位置, 縦位置] = 空中遠近ボリュームの画面位置を求める(横, 縦, 材料.解像度.空中遠近の幅(), 材料.解像度.空中遠近の高さ());
    let 幾何 = 幾何を組む(&材料, 横位置, 縦位置);
    let 積分 = 視線を区間数ぶん積む(
        材料.媒体,
        材料.透過率表,
        材料.多重散乱表,
        &幾何,
        奥 * スライスあたりの標本区間数,
        区間長を求める(&材料),
    )?;
    let 散乱 = 積分.散乱.map(narrowing::実数へ狭める);
    空中遠近ボクセル値::生成する(散乱, narrowing::実数へ狭める(代表透過率へ丸める(積分.通過率)))
}

/// ボリューム全体を走査して各ボクセルの値を求める。GPUが焼いた結果と突き合わせる期待値がこれである。
/// 並びは横が最も速く、次に縦、最後に奥である。GPUの3次元画像を行優先で読み戻した並びと一致する。
pub fn 空中遠近ボリュームを焼く(
    材料: 空中遠近ボリュームの材料<'_>
) -> Result<Vec<空中遠近ボクセル値>, 大気数学エラー> {
    let 幅 = 材料.解像度.空中遠近の幅();
    let 高さ = 材料.解像度.空中遠近の高さ();
    let 奥行き = 材料.解像度.空中遠近の奥行き();
    let mut 一覧 = Vec::with_capacity(材料.解像度.空中遠近のボクセル数());
    for 奥 in 0..奥行き {
        for 縦 in 0..高さ {
            for 横 in 0..幅 {
                一覧.push(空中遠近ボリュームのボクセル値(材料, 横, 縦, 奥)?);
            }
        }
    }
    Ok(一覧)
}

/// 1区間の長さ。最遠距離を「スライスの間隔の数 × スライスあたりの標本区間数」で割る。
/// 割る数が0にならないのは、一辺が2以上であることを大気のベイク済み画像の解像度の生成が保証するためである。
fn 区間長を求める(材料: &空中遠近ボリュームの材料<'_>) -> f64 {
    let 間隔の数 = f64::from(材料.解像度.空中遠近の奥行き() - 1) * f64::from(スライスあたりの標本区間数);
    f64::from(材料.条件.最遠距離().値()) / 間隔の数
}

/// 天頂を+Yに取ったワールドの向きのまま積分の幾何を組む。観測点を惑星中心から真上へ置くのは、
/// 大気の量が半径と太陽との内積だけで決まり、座標軸の取り方に依らないためである。
fn 幾何を組む(材料: &空中遠近ボリュームの材料<'_>, 横位置: f64, 縦位置: f64) -> 視線の幾何 {
    let 観測半径 = f64::from(材料.条件.観測半径(材料.媒体.消散()).値());
    視線の幾何 {
        観測位置: [0.0, 観測半径, 0.0],
        視線: 材料.条件.視錐台の向き().向きを求める(横位置, 縦位置),
        太陽: 材料.条件.太陽方向().生値(),
    }
}
