//! 1本の向きについて経路を刻み、そこで散乱した光と「1回の散乱を経ても残る割合」を積む工程。
//! 受け取るのは媒体・透過率表・観測位置・視線の向き・太陽の向き、返すのはその2つの積分値である。
//!
//! 位相関数を使わず等方(1/4π)で扱うのがHillaire 2020の多重散乱近似である。多重散乱を何度も経た光は
//! 向きの偏りを失うため、位相の形を持ち込まずに済み、散乱の総量だけを1つの伝達率にまとめられる。
//!
//! 注意: この積分は`shaders/atmosphere_multiscatter.slang`の写しを持つ。ここが正本である。

use super::multiscatter_step::{区間の条件, 区間を積む, 地面の照り返しを足す};
use crate::atmosphere::geometry::intersect::最近の球交差距離;
use crate::atmosphere::geometry::vector3::進む;
use crate::atmosphere::table::transmittance_table::透過率表;
use crate::atmosphere::大気散乱媒体;

/// 経路を刻む区間の数。Hillaire 2020実装の多重散乱LUTと同じ20区間を採る。
pub(in crate::atmosphere) const 標本区間数: u32 = 20;
/// 区間の代表点を、その区間の始まりから区間長の何倍だけ進んだ位置に置くか。同出典の値である。
/// 注意: これは区間の中で媒体を評価する位置であって積分幅ではない。消散へ掛ける積分幅は全区間で区間長に等しい。
/// 標本位置の差を積分幅に使うと、最初の区間だけが区間長の0.3倍になり、経路の末尾を積み残す。
const 区間内の標本位置: f64 = 0.3;

/// 1本の向きの積分結果。`放射輝度`が太陽から来て観測点へ届いた光、`残存率`が次の散乱へ渡る割合である。
pub(in crate::atmosphere) struct 経路の積分 {
    pub(in crate::atmosphere) 放射輝度: [f64; 3],
    pub(in crate::atmosphere) 残存率: [f64; 3],
}

pub(in crate::atmosphere) fn 経路を積分する(
    媒体: &大気散乱媒体,
    透過率表: &透過率表,
    観測位置: [f64; 3],
    視線: [f64; 3],
    太陽: [f64; 3],
) -> 経路の積分 {
    let 下端 = f64::from(媒体.消散().下端半径().値());
    let 上端 = f64::from(媒体.消散().上端半径().値());
    let 地表まで = 最近の球交差距離(観測位置, 視線, 下端);
    let 経路長 = 経路長を決める(地表まで, 最近の球交差距離(観測位置, 視線, 上端));
    let mut 積分 = 経路の積分 {
        放射輝度: [0.0; 3],
        残存率: [0.0; 3],
    };
    if 経路長 <= 0.0 {
        return 積分;
    }
    let mut 通過率 = [1.0_f64; 3];
    let 区間長 = 経路長 / f64::from(標本区間数);
    for 区間 in 0..標本区間数 {
        let 標本距離 = (f64::from(区間) + 区間内の標本位置) * 区間長;
        let 条件 = 区間の条件 {
            位置: 進む(観測位置, 視線, 標本距離),
            太陽,
            積分幅: 区間長,
        };
        区間を積む(&mut 積分.放射輝度, &mut 積分.残存率, &mut 通過率, 媒体, 透過率表, &条件);
    }
    // 積分幅の総和が経路長に等しいため、ここへ渡る通過率は観測点から地表までの全経路ぶんである。
    if 地表まで > 0.0 && 経路長 == 地表まで {
        let 地表位置 = 進む(観測位置, 視線, 地表まで);
        地面の照り返しを足す(&mut 積分.放射輝度, 媒体, 透過率表, 地表位置, 太陽, 通過率);
    }
    積分
}

/// 地表と大気上端のどちらへ先に当たるかで経路の終わりを決める。交差の無い向きは負で表され、経路長0になる。
/// スカイビューの積分も同じ決め方を使うため、2つの経路の終わりの定義がこの1箇所で揃う。
pub(in crate::atmosphere) fn 経路長を決める(地表まで: f64, 上端まで: f64) -> f64 {
    if 地表まで < 0.0 {
        return 上端まで.max(0.0);
    }
    if 上端まで < 0.0 {
        return 地表まで;
    }
    地表まで.min(上端まで)
}
