//! カメラから与えられた区間数ぶんだけ視線を刻み、散乱と通過率を積む工程。
//! 受け取るのは媒体・2つの表・視線の幾何・積む区間の数と1区間の長さ、返すのは太陽の放射照度を1としたときの
//! 散乱と、その経路が残す通過率である。
//!
//! 1区間ぶんの積み方はスカイビューと同じ`skyview_step`をそのまま使う。位相関数つきの一次散乱と等方の多重散乱という
//! 源の項が両者で同じでなければ、地平の空と遠景のジオメトリが同じ媒質に見えないためである
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「空中遠近(遠景が大気で霞む効果)は第7段に含める」)。
//!
//! 区間の刻みを全ボクセルで同じ格子に固定し、ボクセルごとに区間数だけを変える。遠いスライスの積分が近いスライスの
//! 積分の厳密な延長になるため、散乱が距離について単調非減少・通過率が単調非増加であることが計算の形から従う。
//!
//! 経路を惑星の地表でも大気上端でも切らない。切る必要が無いのは、規格化密度がどちらの外側でも0になり、消散と源が
//! ともに0になって切る場合と同じ値が出るためである(地表より下は密度分布の第1層が空の層であることから、大気上端より上は
//! 指数分布が0へ落ちることから従う)。切らない形を採るのは、切ると積分の格子がボクセルごとに変わって上の入れ子が
//! 崩れ、単調性が計算の形から従わなくなるからである。
//!
//! 地表より下が真空になることで下向きの視線の遠いスライスが値を持たないが、これは合成の絵に現れない。カメラの高さを
//! h、視線が水平から下へ向く角をθとすると、地形が理想球の上にある限り視線が地形へ当たる距離はh/sinθであり、
//! その距離までの標本点の高度はすべて0以上である。値を失うのは地形より遠いスライスだけであり、その画素の合成が
//! 引くのは地形までの距離のスライスである。
//!
//! 注意: この積分はGPUの生成シェーダーが写しを持つ。ここが正本であり、一致はGPU読み戻し検査が代表ボクセルで確かめる。

use crate::atmosphere::geometry::vector3::進む;
use crate::atmosphere::table::multiscatter_table::多重散乱表;
use crate::atmosphere::table::transmittance_table::透過率表;
use crate::atmosphere::{大気散乱媒体, 大気数学エラー};

use super::skyview_march::位相の組を求める;
use super::skyview_step::{区間を積む, 視線の幾何};

/// 1つの距離スライスを何区間で刻むか。Hillaire 2020実装の空中遠近LUTが1スライスあたり2標本の密度で刻むのに揃える。
/// 出典がスライスごとにカメラから積分し直す形を採るのに対し、ここは同じ格子の上で区間数だけを変えるため、
/// 標本の密度が同じまま単調性が計算の形から従う。
/// 注意: この値はGPUの生成シェーダーの写しと一致していなければならない。区間数が食い違うと同じ式でも
/// 離散化の誤差だけがずれ、読み戻し検査の代表ボクセルが落ちる。
pub(in crate::atmosphere) const スライスあたりの標本区間数: u32 = 2;

/// 区間の中で媒体を評価する位置を、区間の始まりから区間長の何倍だけ進んだ所に置くか。
/// 注意: これは標本位置であって積分幅ではない。消散へ掛ける積分幅は全区間で区間長に等しい。
const 区間内の標本位置: f64 = 0.3;

/// 経路が加えた散乱と、経路が残した通過率。通過率は色ごとに違うため3成分で持ち、代表値への丸めは呼び出し元が行う。
pub(in crate::atmosphere) struct 経路の散乱と通過率 {
    pub(in crate::atmosphere) 散乱: [f64; 3],
    pub(in crate::atmosphere) 通過率: [f64; 3],
}

pub(in crate::atmosphere) fn 視線を区間数ぶん積む(
    媒体: &大気散乱媒体,
    透過率表: &透過率表,
    多重散乱表: &多重散乱表,
    幾何: &視線の幾何,
    区間数: u32,
    区間長: f64,
) -> Result<経路の散乱と通過率, 大気数学エラー> {
    let mut 散乱 = [0.0_f64; 3];
    let mut 通過率 = [1.0_f64; 3];
    if 区間数 == 0 || 区間長 <= 0.0 {
        return Ok(経路の散乱と通過率 { 散乱, 通過率 });
    }
    let 位相 = 位相の組を求める(媒体, 幾何)?;
    for 区間 in 0..区間数 {
        let 標本距離 = (f64::from(区間) + 区間内の標本位置) * 区間長;
        let 位置 = 進む(幾何.観測位置, 幾何.視線, 標本距離);
        区間を積む(&mut 散乱, &mut 通過率, 媒体, 透過率表, 多重散乱表, 幾何, 位置, 区間長, 位相);
    }
    Ok(経路の散乱と通過率 { 散乱, 通過率 })
}

/// 3成分の通過率を1つの代表値へ丸める。等重みの平均を採るのは、色に偏らずに「面の色がどれだけ残るか」を表すためである。
/// 丸めで境界をわずかに越えることがあるため0以上1以下へ切り詰める。
pub(in crate::atmosphere) fn 代表透過率へ丸める(通過率: [f64; 3]) -> f64 {
    ((通過率[0] + 通過率[1] + 通過率[2]) / 3.0).clamp(0.0, 1.0)
}
