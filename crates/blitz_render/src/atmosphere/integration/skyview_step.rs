//! スカイビューの視線上で1区間ぶんを積む操作と、積分が働く座標系の幾何。
//! 受け取るのは積分の途中経過と区間の位置と幅、返り値は無く、渡された途中経過を進めるだけである。
//!
//! 区間の中で消散が一定であるとみなし、閉形式で積む(多重散乱の区間と同じ扱い)。源の項は2つの和である。
//! 一次散乱は太陽への透過率へ位相関数を掛けた向き依存の項であり、多重散乱はベイク済み画像から参照した伝達率へ
//! 散乱係数を掛けた等方の項である。前者だけでは空が暗く、後者だけでは太陽周辺と地平線の色が消える。
//!
//! 注意: この式は`shaders/atmosphere_skyview_march.slang`と`shaders/atmosphere_skyview_geometry.slang`の
//! 写しを持つ。正本はこちらである。

use super::sun_visibility::{太陽が地表に遮られるか, 太陽への透過率を参照する};
use crate::atmosphere::geometry::vector3::{内積, 単位化, 長さ};
use crate::atmosphere::medium::medium_sample::媒体標本;
use crate::atmosphere::table::multiscatter_table::多重散乱表;
use crate::atmosphere::table::transmittance_table::透過率表;
use crate::atmosphere::大気散乱媒体;

/// 積分の対象になる幾何。惑星中心を原点とし、天頂を+Zに取った座標系で与える。
/// 視線と太陽はどちらも単位ベクトルであることを呼び出し元が保証する。
pub(in crate::atmosphere) struct 視線の幾何 {
    pub(in crate::atmosphere) 観測位置: [f64; 3],
    pub(in crate::atmosphere) 視線: [f64; 3],
    pub(in crate::atmosphere) 太陽: [f64; 3],
}

#[allow(clippy::too_many_arguments)]
pub(in crate::atmosphere) fn 区間を積む(
    放射輝度: &mut [f64; 3],
    通過率: &mut [f64; 3],
    媒体: &大気散乱媒体,
    透過率表: &透過率表,
    多重散乱表: &多重散乱表,
    幾何: &視線の幾何,
    位置: [f64; 3],
    積分幅: f64,
    位相: [f64; 2],
) {
    let 標本 = 媒体標本::求める(媒体, 位置);
    let 太陽への透過率 = if 太陽が地表に遮られるか(媒体, 位置, 幾何.太陽) {
        [0.0; 3]
    } else {
        太陽への透過率を参照する(媒体, 透過率表, 位置, 幾何.太陽)
    };
    let 多重散乱 = 多重散乱を参照する(媒体, 多重散乱表, 位置, 幾何.太陽);
    for 添字 in 0..3 {
        let 消散 = 標本.消散係数[添字];
        let 区間透過率 = (-消散 * 積分幅).exp();
        if 消散 > 0.0 {
            let 一次 = 太陽への透過率[添字] * (標本.レイリー散乱係数[添字] * 位相[0] + 標本.ミー散乱係数[添字] * 位相[1]);
            let 多重 = 多重散乱[添字] * 標本.散乱係数[添字];
            let 源 = 一次 + 多重;
            放射輝度[添字] += 通過率[添字] * (源 - 源 * 区間透過率) / 消散;
        }
        通過率[添字] *= 区間透過率;
    }
}

/// その位置の多重散乱の伝達率。太陽天頂余弦と半径から表を参照するだけである。
fn 多重散乱を参照する(媒体: &大気散乱媒体, 多重散乱表: &多重散乱表, 位置: [f64; 3], 太陽: [f64; 3]) -> [f64; 3] {
    let Some(上向き) = 単位化(位置) else {
        return [0.0; 3];
    };
    多重散乱表.標本を参照する(媒体, 内積(上向き, 太陽).clamp(-1.0, 1.0), 長さ(位置))
}
