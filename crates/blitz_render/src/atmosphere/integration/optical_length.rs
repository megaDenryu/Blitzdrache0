//! 視線に沿って規格化密度を積分する工程。受け取るのは密度分布と視線、返すのは光学距離である。
//!
//! 規格化密度は無次元であるため、その線積分は長さの次元を持つ。これに消散係数(逆長さ)を掛けたものが
//! 無次元の光学的深さになる。密度分布ごとに1回だけ積分し、3チャネルぶんの係数は後から掛けるため、
//! 波長ごとに積分を繰り返さずに済む。
//!
//! 積分は台形則である。区間数nに対して標本点をn+1個取り、両端の重みを半分にする。
//! Bruneton 2017実装の`ComputeOpticalLengthToTopAtmosphereBoundary`と同じ刻み方を採ることで、
//! 参照実装との一致検査が離散化の違いでなく式の違いだけを見るようにしている。

use blitz_math::メートル;

use crate::atmosphere::geometry::intersect::上端までの距離の生値;
use crate::atmosphere::medium::density::規格化密度の生値;
use crate::atmosphere::narrowing;
use crate::atmosphere::{大気内観測点, 天頂余弦, 密度分布, 積分標本数};

/// 観測点から大気上端までの光学距離。
///
/// 注意: 視線が地表と交わる場合でも積分は大気上端まで進むため、その結果は地面を貫いた先の大気を含む。
/// 地表に遮られる視線の透過率をこの値から作ってはならない。交差の有無は`視線が惑星と交差するか`で判定する。
pub fn 上端までの光学距離(
    観測点: 大気内観測点<'_>, 分布: &密度分布, 天頂余弦: 天頂余弦, 標本数: 積分標本数
) -> メートル {
    narrowing::長さへ狭める(上端までの光学距離の生値(観測点, 分布, 天頂余弦, 標本数))
}

pub(in crate::atmosphere) fn 上端までの光学距離の生値(
    観測点: 大気内観測点<'_>,
    分布: &密度分布,
    天頂余弦: 天頂余弦,
    標本数: 積分標本数,
) -> f64 {
    let 下端 = f64::from(観測点.媒体().下端半径().値());
    let r = f64::from(観測点.半径().値());
    let mu = f64::from(天頂余弦.値());
    let 区間数 = 標本数.区間数();
    let 刻み = 上端までの距離の生値(f64::from(観測点.媒体().上端半径().値()), r, mu) / f64::from(区間数);
    let mut 合計 = 0.0;
    for 添字 in 0..=区間数 {
        let 進んだ距離 = f64::from(添字) * 刻み;
        let 標本半径 = (進んだ距離 * 進んだ距離 + 2.0 * r * mu * 進んだ距離 + r * r).max(0.0).sqrt();
        let 重み = if 添字 == 0 || 添字 == 区間数 { 0.5 } else { 1.0 };
        合計 += 規格化密度の生値(分布, 標本半径 - 下端) * 重み * 刻み;
    }
    合計
}
