//! 多重散乱の等比級数を1成分ぶん閉じる工程と、その公比が満たすべき上限。
//! 受け取るのは一次散乱の量と等比級数の公比、返すのは無限次の散乱まで足し込んだ放射輝度である。
//!
//! 級数`1 + r + r^2 + ...`が`1 / (1 - r)`へ収束するのは公比が1未満のときである。媒体の基本的なエネルギー条件
//! (散乱係数が消散係数を超えない・地表アルベドが1以下。大気散乱媒体の生成が確かめる)に加えて、この離散近似が
//! 安全に級数を閉じられる対応上限として0.999を要求する。超過は媒体の不正ではなく本アルゴリズムの対応域外であり、
//! 無言で切り詰めず値域外として失敗させる。

use crate::atmosphere::narrowing;
use crate::atmosphere::大気数学エラー;

/// 等比級数の公比が取ってよい上限。数式上の契約は「1未満」であり、そこから丸めの安全幅を引いた値をここに置く。
/// 安全幅が要るのは、同じ媒体の公比をCPUがf64で、GPUがf32で評価するためである。公比は64方向20区間の
/// 総和として作られ、f32の1回の丸めの相対6.0e-8が最悪1280回積もっても相対7.6e-5にとどまる。
/// 1から1.0e-3を引いたこの上限はその13倍の幅を持つため、どちらで評価しても同じ判定へ至る。
///
/// 注意: この値はここが正本であり、`shaders/atmosphere_multiscatter.slang`が同じ値の写しを持つ。
/// 上限に達したときCPUは型付きエラーを返し、失敗を返せないGPUは正常な出力では出ない負値を書く。
/// 両者の値の一致は`cargo xtask conform`が機械検査する。
pub(in crate::atmosphere) const 公比の上限: f64 = 0.999;

pub(in crate::atmosphere) fn 等比級数を閉じる(一次散乱: f64, 公比: f64) -> Result<f32, 大気数学エラー> {
    // NaNもここで捕まえる(比較が偽になるため`公比 < 公比の上限`が成り立たない)。
    if 公比.is_nan() || 公比 >= 公比の上限 {
        return Err(大気数学エラー::値域外(
            "多重散乱の等比級数の公比",
            narrowing::実数へ狭める(公比),
        ));
    }
    Ok(narrowing::実数へ狭める(一次散乱 / (1.0 - 公比)))
}
