//! 光学的深さから透過率を求める工程。受け取るのは視線、返すのはRGBの透過率である。
//!
//! 光学的深さは成分ごとの「消散係数 × 光学距離」の総和であり、透過率はBeer-Lambertの法則により
//! その負の指数になる。成分ごとに光学距離を1回だけ積分し、3チャネルへは係数を掛けるだけにする。

use super::optical_length::上端までの光学距離の生値;
use crate::atmosphere::narrowing;
use crate::atmosphere::{大気内観測点, 天頂余弦, 積分標本数, 透過率RGB};

/// 観測点から大気上端までの透過率。
///
/// 注意: 視線が地表と交わる場合、この値は地面を貫いた先の大気を含むため意味を持たない。
/// 交差の有無は`視線が惑星と交差するか`で判定し、遮られる視線はこの関数へ渡さない。
pub fn 上端までの透過率(観測点: 大気内観測点<'_>, 天頂余弦: 天頂余弦, 標本数: 積分標本数) -> 透過率RGB {
    let mut 光学的深さ = [0.0_f64; 3];
    for 成分 in 観測点.媒体().成分一覧() {
        let 光学距離 = 上端までの光学距離の生値(観測点, &成分.密度分布(), 天頂余弦, 標本数);
        for (添字, 係数) in 成分.消散係数().成分().iter().enumerate() {
            光学的深さ[添字] += f64::from(係数.値()) * 光学距離;
        }
    }
    // 光学的深さは0以上の有限値であるため、その負の指数は0より大きく1以下に収まる。
    透過率RGB::検証済みの成分から(光学的深さ.map(|深さ| narrowing::実数へ狭める((-深さ).exp())))
}
