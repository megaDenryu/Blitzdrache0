//! 散乱角から、その向きへ振り分けられる光の割合を求める工程。
//!
//! どちらの位相関数も全立体角にわたる積分が1になるよう正規化されている。この正規化があるため、
//! 位相関数を掛けた散乱の総量は散乱係数だけで決まり、向きの偏りが明るさの総量を変えない。

use std::f64::consts::PI;

use super::narrowing;
use super::{位相関数値, 位相非対称係数, 散乱角余弦};

/// 空気分子による散乱の角度分布。前方と後方が対称で、真横がその半分になる。
/// 式は`3 / (16 * PI) * (1 + nu^2)`である。
pub fn レイリー位相関数(散乱角余弦: 散乱角余弦) -> 位相関数値 {
    let nu = f64::from(散乱角余弦.値());
    位相関数値::検証済みの値から(narrowing::実数へ狭める(3.0 / (16.0 * PI) * (1.0 + nu * nu)))
}

/// 浮遊粒子による散乱の角度分布。Cornette-Shanks形を採る。
/// Henyey-Greenstein形でなくこの形を採るのは、非対称係数0で厳密にレイリーと同じ角度分布へ帰着し、
/// かつ大きな粒子の前方散乱の鋭さをよく合わせるためである。Bruneton 2017実装とHillaire 2020実装が
/// どちらもこの形を採っており、参照一致検査の比較対象と式を揃える意味もある。
/// 式は`3 / (8 * PI) * (1 - g^2) / (2 + g^2) * (1 + nu^2) / (1 + g^2 - 2 * g * nu)^1.5`である。
pub fn ミー位相関数(位相非対称係数: 位相非対称係数, 散乱角余弦: 散乱角余弦) -> 位相関数値 {
    let g = f64::from(位相非対称係数.値());
    let nu = f64::from(散乱角余弦.値());
    let 係数 = 3.0 / (8.0 * PI) * (1.0 - g * g) / (2.0 + g * g);
    // 非対称係数の絶対値が1未満であることを型が保証するため、この分母は正のままである。
    let 分母 = (1.0 + g * g - 2.0 * g * nu).powf(1.5);
    位相関数値::検証済みの値から(narrowing::実数へ狭める(係数 * (1.0 + nu * nu) / 分母))
}
