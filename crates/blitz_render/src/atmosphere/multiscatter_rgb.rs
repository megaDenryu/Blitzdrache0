//! 太陽の放射照度を1としたときに、無限回の散乱が観測点へ返す放射輝度を赤・緑・青の3成分で表した量。

use super::大気数学エラー;

/// 多重散乱LUTが保持する値。太陽の明るさを掛ける前の伝達率であるため、太陽の強さが変わっても焼き直す必要が無い。
/// 不変条件: 3成分とも有限かつ0以上である。負の放射輝度は物理的に意味を持たない。
/// 上限を置かないのは、地表アルベドが高い大気では無限次散乱の合計が1を超えうるためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 多重散乱RGB {
    成分: [f32; 3],
}

impl 多重散乱RGB {
    pub fn 生成する(赤: f32, 緑: f32, 青: f32) -> Result<Self, 大気数学エラー> {
        let 成分 = [赤, 緑, 青];
        for 値 in 成分 {
            if !値.is_finite() || 値 < 0.0 {
                return Err(大気数学エラー::値域外("多重散乱RGB", 値));
            }
        }
        Ok(Self { 成分 })
    }

    pub fn 成分(&self) -> [f32; 3] {
        self.成分
    }
}
