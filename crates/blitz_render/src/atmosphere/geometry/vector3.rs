//! 惑星中心を原点とする3成分の生ベクトルの演算。多重散乱の積分だけがこの座標系で働くため、
//! 単位付きの値オブジェクトを通さず生値のまま扱う。
//!
//! ここが持つのは進み・単位化・内積・長さの4つだけであり、状態を持たない。
//! 単位型を使わないのは、この座標系が惑星中心基準の一時的なものであり、外へ1つも出ないためである。

pub(in crate::atmosphere) fn 進む(位置: [f64; 3], 向き: [f64; 3], 距離: f64) -> [f64; 3] {
    [位置[0] + 向き[0] * 距離, 位置[1] + 向き[1] * 距離, 位置[2] + 向き[2] * 距離]
}

/// 長さ0のベクトルは向きを持たないため、単位化できないことを`None`で表す。
pub(in crate::atmosphere) fn 単位化(値: [f64; 3]) -> Option<[f64; 3]> {
    let 大きさ = 長さ(値);
    (大きさ > 0.0).then(|| [値[0] / 大きさ, 値[1] / 大きさ, 値[2] / 大きさ])
}

pub(in crate::atmosphere) fn 内積(左: [f64; 3], 右: [f64; 3]) -> f64 {
    左[0] * 右[0] + 左[1] * 右[1] + 左[2] * 右[2]
}

pub(in crate::atmosphere) fn 長さ(値: [f64; 3]) -> f64 {
    内積(値, 値).max(0.0).sqrt()
}
