//! カメラの視錐台を、画面の単位位置から視線の向きを返す1つのアフィン写像として表す型。
//!
//! 4隅の向きを持たず基準と2つの差分で持つのは、遠平面上の点はクリップ座標のwが一定であり、画面の単位位置に対する
//! 向きの写像がアフィンになるためである。アフィンなら基準1つと差分2つで厳密に表せ、4隅を持つと同じ情報を
//! 冗長に持つことになる。全画面三角形の頂点段が頂点間の線形補間で画素ごとの向きを得ているのと同じ根拠である
//! (参照: `shaders/sky_frame.slang`の`vertexMain`)。
//!
//! 向きは天頂を+Yに取ったワールドの向きであり、大域原点に依らない。カメラの位置を持たないことがカメラ相対契約を
//! 型のうえで保証する(参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「大気LUT方式の設計(第7段で実装する)」)。

use crate::atmosphere::geometry::vector3::単位化;
use crate::atmosphere::大気数学エラー;

/// 画面の単位位置(横0が左・縦0が上)から視線の向きを与えるアフィン写像。
/// 不変条件: 3つのベクトルの全成分が有限であり、基準の向きは長さ0でない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 視錐台の向き {
    基準: [f64; 3],
    横の差分: [f64; 3],
    縦の差分: [f64; 3],
}

impl 視錐台の向き {
    pub fn 生成する(基準: [f32; 3], 横の差分: [f32; 3], 縦の差分: [f32; 3]) -> Result<Self, 大気数学エラー> {
        for (項目, 成分一覧) in [
            ("視錐台の基準の向き", 基準),
            ("視錐台の横の差分", 横の差分),
            ("視錐台の縦の差分", 縦の差分),
        ] {
            for 値 in 成分一覧 {
                if !値.is_finite() {
                    return Err(大気数学エラー::値域外(項目, 値));
                }
            }
        }
        let 基準 = 倍精度へ広げる(基準);
        if 単位化(基準).is_none() {
            return Err(大気数学エラー::値域外("視錐台の基準の向きの長さ", 0.0));
        }
        Ok(Self {
            基準,
            横の差分: 倍精度へ広げる(横の差分),
            縦の差分: 倍精度へ広げる(縦の差分),
        })
    }

    /// 画面の単位位置に対応する視線の単位ベクトル。
    /// 単位化できない位置があり得るのは差分が基準を打ち消す場合だけであり、遠平面の四角形が退化していない限り起きない。
    /// 起きた場合に基準の向きへ落とすのは、退化した視錐台でボクセルの値を欠かすより、画面全体で同じ向きを見る方が
    /// 検査で気付ける形だからである。
    pub fn 向きを求める(&self, 横位置: f64, 縦位置: f64) -> [f64; 3] {
        let 生の向き = [0, 1, 2].map(|軸| self.基準[軸] + self.横の差分[軸] * 横位置 + self.縦の差分[軸] * 縦位置);
        単位化(生の向き).or_else(|| 単位化(self.基準)).unwrap_or([0.0, 1.0, 0.0])
    }
}

fn 倍精度へ広げる(値: [f32; 3]) -> [f64; 3] {
    [f64::from(値[0]), f64::from(値[1]), f64::from(値[2])]
}
