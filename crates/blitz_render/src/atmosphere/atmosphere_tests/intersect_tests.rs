//! 視線と球の交差の検査。閉形式との一致、地平線の余弦の定義、交差判定と地平線の整合を見る。

use super::super::{
    地平線の天頂余弦, 大気上端までの距離, 大気内観測点, 天頂余弦, 惑星までの距離, 消散媒体, 視線が惑星と交差するか
};
use super::{m, 上端半径, 下端半径, 地球標準の媒体};

fn 観測点(媒体: &消散媒体, 値: f32) -> 大気内観測点<'_> {
    大気内観測点::生成する(媒体, m(値)).unwrap()
}

fn 余弦(値: f32) -> 天頂余弦 {
    天頂余弦::生成する(値).unwrap()
}

#[test]
fn 真上を向いた視線は大気の厚みちょうどで上端へ届く() {
    let 媒体 = 地球標準の媒体();
    let 距離 = 大気上端までの距離(観測点(&媒体, 下端半径), 余弦(1.0)).値();
    assert!((距離 - (上端半径 - 下端半径)).abs() < 1.0, "{距離}");
}

/// 地平線の天頂余弦は接線の条件から -sqrt(1 - (下端半径 / 半径)^2) である。
#[test]
fn 地平線の天頂余弦が閉形式と一致する() {
    let 媒体 = 地球標準の媒体();
    for 高度 in [0.0_f32, 1000.0, 10_000.0, 50_000.0, 99_000.0] {
        let 実測 = 地平線の天頂余弦(観測点(&媒体, 下端半径 + 高度)).値();
        let 比 = f64::from(下端半径) / f64::from(下端半径 + 高度);
        let 期待 = -(1.0 - 比 * 比).sqrt();
        assert!((f64::from(実測) - 期待).abs() < 1e-6, "高度{高度}で{実測}と{期待}が食い違う");
    }
    assert!((地平線の天頂余弦(観測点(&媒体, 下端半径)).値()).abs() < 1e-7);
}

/// 上端までの距離は2次方程式の正の解であり、その点の半径がちょうど上端半径になる。
#[test]
fn 上端までの距離の到達点が上端半径になる() {
    let 媒体 = 地球標準の媒体();
    for 高度 in [0.0_f32, 20_000.0, 80_000.0] {
        for mu in [-1.0_f32, -0.5, -0.05, 0.0, 0.05, 0.5, 1.0] {
            let r = f64::from(下端半径 + 高度);
            let d = f64::from(大気上端までの距離(観測点(&媒体, 下端半径 + 高度), 余弦(mu)).値());
            let 到達半径 = (d * d + 2.0 * r * f64::from(mu) * d + r * r).sqrt();
            assert!((到達半径 - f64::from(上端半径)).abs() < 2.0, "高度{高度}のmu={mu}で{到達半径}");
        }
    }
}

#[test]
fn 地平線より下を向く視線だけが地表と交わる() {
    let 媒体 = 地球標準の媒体();
    for 高度 in [0.0_f32, 1000.0, 50_000.0] {
        let 観測点 = 観測点(&媒体, 下端半径 + 高度);
        let 地平線 = 地平線の天頂余弦(観測点).値();
        assert!(視線が惑星と交差するか(観測点, 余弦((地平線 - 1e-4).max(-1.0))));
        assert!(!視線が惑星と交差するか(観測点, 余弦(地平線 + 1e-4)));
        assert!(!視線が惑星と交差するか(観測点, 余弦(1.0)));
    }
}

#[test]
fn 真下を向いた視線は高度ちょうどで地表へ届く() {
    let 媒体 = 地球標準の媒体();
    let 距離 = 惑星までの距離(観測点(&媒体, 下端半径 + 10_000.0), 余弦(-1.0)).map(|長さ| 長さ.値());
    assert!(距離.is_some_and(|値| (値 - 10_000.0).abs() < 1.0), "{距離:?}");
    assert!(惑星までの距離(観測点(&媒体, 下端半径 + 10_000.0), 余弦(1.0)).is_none());
}

/// 観測点は自分を検証した媒体を持ち運ぶため、高度は必ずその媒体の地表から測った値になる。
/// 半径と媒体が別々の引数だった頃は、ある媒体で作った半径を別の媒体の計算へ渡せ、この対応が崩れる形だった。
#[test]
fn 観測点の高度は自分の媒体の地表から測る() {
    let 地球 = 地球標準の媒体();
    let 地表が低い媒体 = 消散媒体::生成する(m(下端半径 - 1000.0), m(上端半径), 地球.レイリー(), 地球.ミー(), 地球.吸収()).unwrap();
    assert!((観測点(&地球, 下端半径 + 5000.0).高度().値() - 5000.0).abs() < 1.0);
    assert!((観測点(&地表が低い媒体, 下端半径 + 5000.0).高度().値() - 6000.0).abs() < 1.0);
}
