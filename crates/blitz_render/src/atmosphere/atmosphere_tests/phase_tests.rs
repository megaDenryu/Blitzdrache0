//! 位相関数の検査。球面全体にわたる積分が1へ正規化されていること、既知の閉じた値、非対称係数0での一致を見る。

use super::super::{ミー位相関数, レイリー位相関数, 位相非対称係数, 散乱角余弦};

const 積分区間数: u32 = 1_000_000;

/// 方位角に依存しないため、球面積分は`2 * PI * ∫ p(nu) dnu`へ落ちる。台形則で刻む。
fn 球面積分(評価: impl Fn(f32) -> f32) -> f64 {
    let 刻み = 2.0 / f64::from(積分区間数);
    let mut 合計 = 0.0;
    for 添字 in 0..=積分区間数 {
        let nu = -1.0 + f64::from(添字) * 刻み;
        let 重み = if 添字 == 0 || 添字 == 積分区間数 { 0.5 } else { 1.0 };
        let 標本 = super::super::narrowing::実数へ狭める(nu.clamp(-1.0, 1.0));
        合計 += f64::from(評価(標本)) * 重み * 刻み;
    }
    合計 * 2.0 * std::f64::consts::PI
}

fn 余弦(値: f32) -> 散乱角余弦 {
    散乱角余弦::生成する(値).unwrap()
}

/// 区間数100万での実測の誤差は、レイリーが9.5e-12、ミーが非対称係数-0.7で8.8e-11、0で9.5e-12、
/// 0.3で1.3e-11、0.8で2.9e-10である。前方散乱が鋭いほど台形則の離散化誤差が増えるため、
/// 最大は非対称係数0.8で出る。判定はその最大の30倍にあたる1e-8を上限とする。
#[test]
fn 位相関数の球面積分が1に正規化されている() {
    let レイリー積分 = 球面積分(|nu| レイリー位相関数(余弦(nu)).毎ステラジアン());
    assert!((レイリー積分 - 1.0).abs() < 1e-8, "レイリーの積分{レイリー積分}");
    for g in [-0.7_f32, 0.0, 0.3, 0.8] {
        let 係数 = 位相非対称係数::生成する(g).unwrap();
        let ミー積分 = 球面積分(|nu| ミー位相関数(係数, 余弦(nu)).毎ステラジアン());
        assert!((ミー積分 - 1.0).abs() < 1e-8, "非対称係数{g}の積分{ミー積分}");
    }
}

/// Cornette-Shanks形は非対称係数0でレイリー位相関数と厳密に一致する。
/// 3/(8*PI) * (1/2) * (1 + nu^2) = 3/(16*PI) * (1 + nu^2) であるためである。
#[test]
fn 非対称係数0のミーはレイリーと一致する() {
    let 係数 = 位相非対称係数::生成する(0.0).unwrap();
    for nu in [-1.0_f32, -0.5, 0.0, 0.5, 1.0] {
        let レイリー = レイリー位相関数(余弦(nu)).毎ステラジアン();
        let ミー = ミー位相関数(係数, 余弦(nu)).毎ステラジアン();
        assert!((レイリー - ミー).abs() <= 1e-7 * レイリー, "nu={nu}で{レイリー}と{ミー}");
    }
}

#[test]
fn レイリー位相関数が閉形式と一致する() {
    for nu in [-1.0_f32, -0.5, 0.0, 0.5, 1.0] {
        let 期待 = 3.0 / (16.0 * std::f64::consts::PI) * (1.0 + f64::from(nu) * f64::from(nu));
        let 実測 = f64::from(レイリー位相関数(余弦(nu)).毎ステラジアン());
        assert!((実測 - 期待).abs() <= 1e-7 * 期待, "nu={nu}で{実測}と{期待}");
    }
}

/// 前方散乱に偏る非対称係数では、前方の値が後方の値より大きい。
#[test]
fn 正の非対称係数は前方が後方より明るい() {
    let 係数 = 位相非対称係数::生成する(0.8).unwrap();
    let 前方 = ミー位相関数(係数, 余弦(1.0)).毎ステラジアン();
    let 後方 = ミー位相関数(係数, 余弦(-1.0)).毎ステラジアン();
    assert!(前方 > 後方, "前方{前方}、後方{後方}");
}
