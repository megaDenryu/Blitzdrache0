//! 参照データの1行が表す内容。種別ごとに引数と期待値の数が違うため、判別共用体で表す。

/// Bruneton参照が焼いた1件の期待値。数値はすべてf64のまま持ち、比較のときにだけf32へ狭める。
#[derive(Debug, Clone, PartialEq)]
pub(super) enum 参照レコード {
    /// 焼いた条件の大気パラメータ。名前と値の組である。
    パラメータ { 名前: String, 値: f64 },
    /// 高度に対する3成分の規格化密度。
    密度 {
        高度: f64, レイリー: f64, ミー: f64, 吸収: f64
    },
    /// 観測点の半径に対する地平線の天頂余弦。
    地平線 { 半径: f64, 天頂余弦: f64 },
    /// 大気上端までの距離。
    上端距離 { 半径: f64, 天頂余弦: f64, 距離: f64 },
    /// 地表までの距離。地表と交わる視線についてだけ焼いてある。
    地表距離 { 半径: f64, 天頂余弦: f64, 距離: f64 },
    /// 上端までの3成分の光学距離。
    光学距離 {
        半径: f64,
        天頂余弦: f64,
        レイリー: f64,
        ミー: f64,
        吸収: f64,
    },
    /// 上端までのRGB透過率。
    透過率 { 半径: f64, 天頂余弦: f64, 成分: [f64; 3] },
    /// 散乱角余弦に対する2つの位相関数の値。
    位相 { 散乱角余弦: f64, レイリー: f64, ミー: f64 },
}
