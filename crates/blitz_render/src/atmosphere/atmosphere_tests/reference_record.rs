//! 参照データの1行が表す内容。種別ごとに引数と期待値の数が違うため、判別共用体で表す。

/// Bruneton参照が焼いた1件の期待値。数値はすべてf64のまま持ち、比較のときにだけf32へ狭める。
///
/// `パラメータ`は焼いた条件の大気パラメータであり、名前と値の組である。
/// `密度`は高度に対する3成分の規格化密度である。
/// `地平線`は観測点の半径に対する地平線の天頂余弦である。
/// `上端距離`は大気上端までの距離である。
/// `地表距離`は地表までの距離であり、地表と交わる視線についてだけ焼いてある。
/// `光学距離`は上端までの3成分の光学距離である。
/// `透過率`は上端までのRGB透過率である。
/// `位相`は散乱角余弦に対する2つの位相関数の値である。
#[derive(Debug, Clone, PartialEq)]
pub(super) enum 参照レコード {
    パラメータ {
        名前: String,
        値: f64,
    },
    密度 {
        高度: f64,
        レイリー: f64,
        ミー: f64,
        吸収: f64,
    },
    地平線 {
        半径: f64,
        天頂余弦: f64,
    },
    上端距離 {
        半径: f64,
        天頂余弦: f64,
        距離: f64,
    },
    地表距離 {
        半径: f64,
        天頂余弦: f64,
        距離: f64,
    },
    光学距離 {
        半径: f64,
        天頂余弦: f64,
        レイリー: f64,
        ミー: f64,
        吸収: f64,
    },
    透過率 {
        半径: f64,
        天頂余弦: f64,
        成分: [f64; 3],
    },
    位相 {
        散乱角余弦: f64,
        レイリー: f64,
        ミー: f64,
    },
}
