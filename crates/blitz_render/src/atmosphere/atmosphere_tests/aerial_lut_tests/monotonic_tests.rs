//! 空中遠近ボリュームの距離に対する単調性の検査。遠いスライスの積分が近いスライスの積分の厳密な延長であることを、
//! どの画面位置でも成り立つ非狭義の単調性と、大気の中に留まる視線での狭義の単調性の2つで見る。

use super::{ボクセル, 代表の画面位置, 材料を組む, 検査の一辺};

/// どの画面の位置でも、遠いスライスの散乱が手前を下回らず、透過率が手前を上回らない。
/// 下向きの視線は理想球の下へ抜けた先が真空になるため増分が0になりうる。等号を許すのはそのためである。
#[test]
fn 距離が遠いほど散乱が減らず透過率が増えない() {
    let 材料 = 材料を組む();
    for (横, 縦) in 代表の画面位置() {
        for 奥 in 1..検査の一辺 {
            let 手前 = ボクセル(&材料, 0.5, 横, 縦, 奥 - 1);
            let 奥側 = ボクセル(&材料, 0.5, 横, 縦, 奥);
            for (添字, (手前値, 奥値)) in 手前.散乱の成分().into_iter().zip(奥側.散乱の成分()).enumerate() {
                assert!(奥値 >= 手前値, "横{横}縦{縦}奥{奥}の成分{添字}が手前{手前値}に対して{奥値}");
            }
            let (手前の透過率, 奥の透過率) = (手前.代表透過率(), 奥側.代表透過率());
            assert!(
                奥の透過率 <= 手前の透過率,
                "横{横}縦{縦}奥{奥}の透過率が手前{手前の透過率}に対して{奥の透過率}"
            );
        }
    }
}

/// 大気の中に留まる上向きの視線では、遠いスライスの散乱が厳密に増え透過率が厳密に減る。
/// 区間数を無視して常に同じ経路を積む実装は非狭義の単調性を満たしてしまうため、狭義の検査で落とす。
#[test]
fn 上向きの視線では散乱が厳密に増えて透過率が厳密に減る() {
    let 材料 = 材料を組む();
    let 横 = 検査の一辺 / 2;
    for 奥 in 1..検査の一辺 {
        let 手前 = ボクセル(&材料, 0.5, 横, 0, 奥 - 1);
        let 奥側 = ボクセル(&材料, 0.5, 横, 0, 奥);
        for (添字, (手前値, 奥値)) in 手前.散乱の成分().into_iter().zip(奥側.散乱の成分()).enumerate() {
            assert!(奥値 > 手前値, "奥{奥}の成分{添字}が手前{手前値}に対して{奥値}");
        }
        let (手前の透過率, 奥の透過率) = (手前.代表透過率(), 奥側.代表透過率());
        assert!(奥の透過率 < 手前の透過率, "奥{奥}の透過率が手前{手前の透過率}に対して{奥の透過率}");
    }
}
