//! 空中遠近ボリュームの値域と境界の検査。散乱が有限かつ非負で代表透過率が0以上1以下であること、
//! および距離0のスライスが厳密に散乱0・透過率1であることを見る。

use super::{ボクセル, 代表の画面位置, 材料を組む, 検査の一辺};

/// 全てのボクセルの散乱が有限かつ非負であり、代表透過率が0以上1以下である。
#[test]
fn 代表ボクセルが値域に収まる() {
    let 材料 = 材料を組む();
    for 奥 in 0..検査の一辺 {
        for (横, 縦) in 代表の画面位置() {
            let 値 = ボクセル(&材料, 0.5, 横, 縦, 奥);
            for 成分 in 値.散乱の成分() {
                assert!(成分.is_finite() && 成分 >= 0.0, "横{横}縦{縦}奥{奥}の散乱が{成分}");
            }
            let 透過率 = 値.代表透過率();
            assert!(
                透過率.is_finite() && (0.0..=1.0).contains(&透過率),
                "横{横}縦{縦}奥{奥}の透過率が{透過率}"
            );
        }
    }
}

/// 先頭のスライスは距離0を表すため、散乱が厳密に0で透過率が厳密に1である。
/// 経路が1区間も無いことが計算の形から従うため、丸めの許容を置かずに厳密な一致を要求する。
#[test]
fn 距離0のスライスは散乱0で透過率1である() {
    let 材料 = 材料を組む();
    for (横, 縦) in 代表の画面位置() {
        let 値 = ボクセル(&材料, 0.5, 横, 縦, 0);
        assert_eq!(値.散乱の成分(), [0.0, 0.0, 0.0], "横{横}縦{縦}の散乱");
        assert_eq!(値.代表透過率(), 1.0, "横{横}縦{縦}の透過率");
    }
}
