//! 空中遠近ボリュームの走査の並びと、画面の位置が値へ効くことの検査。
//! 並びの検査が要るのは、平坦な列の添字計算が読み戻し検査の前提であり、並びが違うと代表ボクセルが別のボクセルと
//! 突き合わされて誤差の判定が意味を失うからである。

use crate::atmosphere::空中遠近ボリュームを焼く;

use super::{ボクセル, 材料を組む, 検査の一辺};

/// ボリューム全体の走査が、ボクセル数ぶんの要素を「横が最も速く、次に縦、最後に奥」の並びで返す。
/// この並びはGPUの3次元画像を行優先で読み戻した並びと一致する契約である。
#[test]
fn 走査の並びが横縦奥の順である() {
    let 材料 = 材料を組む();
    let 一覧 = 空中遠近ボリュームを焼く(材料.束にする(0.5)).unwrap();
    assert_eq!(一覧.len(), 材料.解像度().空中遠近のボクセル数());
    let 一辺 = usize::try_from(検査の一辺).unwrap();
    for (横, 縦, 奥) in [(1_u32, 2_u32, 3_u32), (7, 0, 5), (0, 7, 7)] {
        let 添字 = usize::try_from(奥).unwrap() * 一辺 * 一辺 + usize::try_from(縦).unwrap() * 一辺 + usize::try_from(横).unwrap();
        let 期待 = ボクセル(&材料, 0.5, 横, 縦, 奥);
        assert_eq!(一覧[添字].散乱の成分(), 期待.散乱の成分(), "横{横}縦{縦}奥{奥}の散乱");
        assert_eq!(一覧[添字].代表透過率(), 期待.代表透過率(), "横{横}縦{縦}奥{奥}の透過率");
    }
}

/// 太陽の側を向いた画素は反対側を向いた画素より散乱が明るい。位相関数の前方散乱の偏りが画面の横位置で効くことの検査である。
#[test]
fn 太陽の側の画素が反対側より明るい() {
    let 材料 = 材料を組む();
    let 奥 = 検査の一辺 - 1;
    let 縦 = 検査の一辺 / 2;
    let 太陽側: f32 = ボクセル(&材料, 0.2, 検査の一辺 - 1, 縦, 奥).散乱の成分().iter().sum();
    let 反対側: f32 = ボクセル(&材料, 0.2, 0, 縦, 奥).散乱の成分().iter().sum();
    assert!(太陽側 > 反対側, "太陽側{太陽側}に対して反対側{反対側}");
}

/// 同じ入力を2回焼くと完全に一致する。履歴も乱数も持たないことの検査である。
#[test]
fn 同じ入力を2回焼くと完全に一致する() {
    let 材料 = 材料を組む();
    let 一回目 = ボクセル(&材料, 0.4, 3, 5, 6);
    let 二回目 = ボクセル(&材料, 0.4, 3, 5, 6);
    assert_eq!(一回目.散乱の成分(), 二回目.散乱の成分());
    assert_eq!(一回目.代表透過率(), 二回目.代表透過率());
}
