//! 等比級数の公比の上限が契約として働くことの検査。上限そのものを直に見る検査と、
//! 上限を挟む極端な媒体を焼く検査の2つで見る。
//!
//! GPU側は同じ上限の写しを持ち、上限に達したテクセルへ負値を書く。定数の値が一致することは
//! `cargo xtask conform`が、負値が読み戻し検査で不合格になることは`cargo xtask atmosphere-lut`が受け持つ。

use super::m;
use crate::atmosphere::integration::multiscatter_series::{公比の上限, 等比級数を閉じる};
use crate::atmosphere::{
    位相非対称係数, 地表アルベドRGB, 多重散乱のベイク済み画像のテクセル値, 大気のベイク済み画像の解像度, 大気散乱媒体, 大気数学エラー, 密度分布,
    消散係数RGB, 消散媒体, 減衰成分, 透過率表,
};

/// 上限のすぐ下の公比は、無限次まで足し込んだ有限の値を返す。
#[test]
fn 公比が上限の直下なら級数を閉じる() {
    let 閉じた = 等比級数を閉じる(1.0e-3, 公比の上限 - 1.0e-9).unwrap();
    assert!(閉じた.is_finite() && 閉じた > 0.0, "閉じた値が{閉じた}");
}

/// 上限に達した公比とNaNは、無言で切り詰めず値域外として失敗する。
#[test]
fn 公比が上限に達したら値域外で失敗する() {
    for 公比 in [公比の上限, 1.0, 1.5, f64::NAN] {
        let 結果 = 等比級数を閉じる(1.0e-3, 公比);
        assert!(
            matches!(結果, Err(大気数学エラー::値域外 { 項目, .. }) if 項目 == "多重散乱の等比級数の公比"),
            "公比{公比}が値域外にならない"
        );
    }
}

/// 光学的に極端に厚く、単一散乱アルベドが指定の値をとる媒体。散乱と消散を同じ密度分布のレイリー成分だけで作るため、
/// 単一散乱アルベドは高度によらず一定になる。地表付近のテクセルではどの向きも経路の透過率が0へ落ちるため、
/// 等比級数の公比は単一散乱アルベドそのものへ一致する。この性質があるので、上限を挟む2つの公比を媒体から作れる。
fn 極端に厚い媒体(単一散乱アルベド: f32) -> 大気散乱媒体 {
    let 毎メートルの消散: f32 = 1.0;
    let レイリー = 減衰成分::生成する(
        消散係数RGB::毎メートルから(毎メートルの消散, 毎メートルの消散, 毎メートルの消散).unwrap(),
        密度分布::指数分布(m(8000.0)).unwrap(),
    );
    let ミー無し = 減衰成分::生成する(
        消散係数RGB::毎メートルから(0.0, 0.0, 0.0).unwrap(),
        密度分布::指数分布(m(1200.0)).unwrap(),
    );
    let 吸収無し = 減衰成分::生成する(
        消散係数RGB::毎メートルから(0.0, 0.0, 0.0).unwrap(),
        密度分布::テント(m(10_000.0), m(25_000.0), m(40_000.0)).unwrap(),
    );
    let 消散 = 消散媒体::生成する(m(super::下端半径), m(super::上端半径), レイリー, ミー無し, 吸収無し).unwrap();
    let 散乱 = 毎メートルの消散 * 単一散乱アルベド;
    大気散乱媒体::生成する(
        消散,
        消散係数RGB::毎メートルから(散乱, 散乱, 散乱).unwrap(),
        消散係数RGB::毎メートルから(0.0, 0.0, 0.0).unwrap(),
        位相非対称係数::生成する(0.0).unwrap(),
        地表アルベドRGB::生成する(0.0, 0.0, 0.0).unwrap(),
    )
    .unwrap()
}

/// 地表付近のテクセルを焼く。この行はどの向きの経路も光学的に厚く、公比が単一散乱アルベドに一致する。
fn 地表付近を焼く(単一散乱アルベド: f32) -> Result<[f32; 3], 大気数学エラー> {
    let 媒体 = 極端に厚い媒体(単一散乱アルベド);
    let 解像度 = 大気のベイク済み画像の解像度::既定値();
    let 表 = 透過率表::焼く(媒体.消散(), 解像度)?;
    Ok(多重散乱のベイク済み画像のテクセル値(&媒体, &表, 解像度, 16, 0)?.成分())
}

/// 公比が上限の1.0e-3下にある媒体は、契約の内側として最後まで焼ける。
#[test]
fn 公比が上限の直下になる媒体を焼ける() {
    let 値 = 地表付近を焼く(0.998).unwrap();
    for 成分 in 値 {
        assert!(成分.is_finite() && 成分 >= 0.0, "焼いた値が{成分}");
    }
}

/// 公比が上限の5.0e-4上にある媒体は、型が受理する入力であっても等比級数の公比として失敗する。
/// 上の検査と合わせて、媒体から作った公比が上限の前後1.5e-3の幅で判定を切り替えることを示す。
#[test]
fn 公比が上限を超える媒体は値域外で失敗する() {
    let 結果 = 地表付近を焼く(0.9995);
    assert!(
        matches!(結果, Err(大気数学エラー::値域外 { 項目, .. }) if 項目 == "多重散乱の等比級数の公比"),
        "上限を超える媒体が失敗しない"
    );
}
