//! 密度分布の検査。指数分布が閉形式と一致すること、テント関数が3つの高度で設計どおりの値を取ることを見る。

use super::super::{密度分布, 規格化密度を求める};
use super::{m, レイリー尺度高度, 吸収上端高度, 吸収下端高度, 吸収頂点高度};

#[test]
fn 指数分布は閉形式と一致する() {
    let 分布 = 密度分布::指数分布(m(レイリー尺度高度)).unwrap();
    for 高度 in [0.0_f32, 1000.0, 8000.0, 25_000.0, 60_000.0] {
        let 期待 = (-高度 / レイリー尺度高度).exp();
        let 実測 = 規格化密度を求める(&分布, m(高度)).値();
        assert!((実測 - 期待).abs() <= 1e-6 * 期待.max(1e-6), "高度{高度}で{実測}と{期待}が食い違う");
    }
}

#[test]
fn 指数分布は地表で1になり高さとともに単調に減る() {
    let 分布 = 密度分布::指数分布(m(レイリー尺度高度)).unwrap();
    assert!((規格化密度を求める(&分布, m(0.0)).値() - 1.0).abs() < 1e-6);
    let mut 前 = 1.0_f32;
    for 段 in 1..=100u8 {
        let 値 = 規格化密度を求める(&分布, m(f32::from(段) * 1000.0)).値();
        assert!(値 <= 前, "高度{段}kmで密度が増えた");
        前 = 値;
    }
}

#[test]
fn テント分布は3つの高度で0と1を取る() {
    let 分布 = 密度分布::テント(m(吸収下端高度), m(吸収頂点高度), m(吸収上端高度)).unwrap();
    assert!(規格化密度を求める(&分布, m(0.0)).値() < 1e-6);
    assert!(規格化密度を求める(&分布, m(吸収下端高度)).値() < 1e-6);
    assert!((規格化密度を求める(&分布, m(吸収頂点高度)).値() - 1.0).abs() < 1e-6);
    assert!(規格化密度を求める(&分布, m(吸収上端高度)).値() < 1e-6);
    assert!(規格化密度を求める(&分布, m(100_000.0)).値() < 1e-6);
    let 中点 = (吸収下端高度 + 吸収頂点高度) / 2.0;
    assert!((規格化密度を求める(&分布, m(中点)).値() - 0.5).abs() < 1e-6);
}

/// 規格化密度は定義から0以上1以下であり、極端な高度でもその範囲を出ない。
#[test]
fn どの高度でも0以上1以下の有限値になる() {
    let 分布一覧 = [
        密度分布::指数分布(m(レイリー尺度高度)).unwrap(),
        密度分布::テント(m(吸収下端高度), m(吸収頂点高度), m(吸収上端高度)).unwrap(),
    ];
    for 分布 in 分布一覧 {
        for 段 in -10..=200i16 {
            let 値 = 規格化密度を求める(&分布, m(f32::from(段) * 1000.0)).値();
            assert!(値.is_finite() && (0.0..=1.0).contains(&値), "高度{段}kmで{値}");
        }
    }
}
