//! 多重散乱のベイク済み画像の写像と逆写像の検査。焼く側の写像と、スカイビューの積分が表を参照するときの逆写像が
//! 往復で一致することを見る。軸の両端が何を表すかと焼いた値は`multiscatter_lut_tests`が別に見る。

use blitz_math::メートル;

use super::地球標準の媒体;
use crate::atmosphere::{
    多重散乱のベイク済み画像の単位位置を求める, 多重散乱のベイク済み画像の条件を求める, 大気のベイク済み画像の解像度, 端から端への単位位置,
};

/// 条件から単位位置へ戻す逆写像が、焼く側の写像と往復で一致する。
/// スカイビューの積分がこの逆写像で表を参照するため、ここがずれると多重散乱の項だけが半テクセルずれる。
///
/// 最上行だけを対象から外すのは、焼く側の写像が高さの割合を1で頭打ちにしており、そこだけ単射でないためである
/// (割合は`縦位置 + 最下行を地表から離す割合`であり、縦位置0.99で上限に達する)。最上行の扱いは別の検査が見る。
#[test]
fn 条件と単位位置の往復が恒等である() {
    let 媒体 = 地球標準の媒体();
    let 解像度 = 大気のベイク済み画像の解像度::既定値();
    let 一辺 = 解像度.多重散乱の一辺();
    for 縦 in [0, 7, 一辺 / 2, 一辺 - 2] {
        for 横 in [0, 一辺 / 2, 一辺 - 1] {
            let 条件 = 多重散乱のベイク済み画像の条件を求める(&媒体, 解像度, 横, 縦).unwrap();
            let [戻り横, 戻り縦] =
                多重散乱のベイク済み画像の単位位置を求める(&媒体, f64::from(条件.太陽天頂余弦.値()), f64::from(条件.半径.値()));
            let 期待横 = f64::from(端から端への単位位置(横, 一辺));
            let 期待縦 = f64::from(端から端への単位位置(縦, 一辺));
            assert!((戻り横 - 期待横).abs() < 1.0e-5, "横{横}が{戻り横}(期待{期待横})");
            assert!((戻り縦 - 期待縦).abs() < 1.0e-4, "縦{縦}が{戻り縦}(期待{期待縦})");
        }
    }
}

/// 焼く側が頭打ちにしている最上行は、逆写像が0.99へ写る。頭打ちのぶんだけ参照する位置が内側へ寄るが、
/// ずれは32テクセルの軸で0.32テクセルであり、大気上端付近の多重散乱がほぼ0であるため絵に現れない。
/// 大気の外へ出た半径も範囲内へ切り詰める(視線の標本点は大気内にあるが、丸めで境界をわずかに越えうる)。
#[test]
fn 最上行と大気外の半径が範囲内へ収まる() {
    let 媒体 = 地球標準の媒体();
    let 解像度 = 大気のベイク済み画像の解像度::既定値();
    let 最上行 = 多重散乱のベイク済み画像の条件を求める(&媒体, 解像度, 16, 解像度.多重散乱の一辺() - 1).unwrap();
    let [_, 最上行の縦] = 多重散乱のベイク済み画像の単位位置を求める(&媒体, 0.0, f64::from(最上行.半径.値()));
    assert!((最上行の縦 - 0.99).abs() < 1.0e-4, "最上行の縦位置が{最上行の縦}");
    let 大気の外 = f64::from(super::上端半径) + f64::from(メートル::生成する(1000.0).値());
    let [_, 外の縦] = 多重散乱のベイク済み画像の単位位置を求める(&媒体, 0.5, 大気の外);
    assert!((外の縦 - 1.0).abs() < 1.0e-9, "大気の外の縦位置が{外の縦}");
}
