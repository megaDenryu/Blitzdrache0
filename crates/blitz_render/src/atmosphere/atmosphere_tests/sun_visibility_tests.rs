//! 太陽の遮蔽判定の検査。自己交差の回避が判定を反転させないこと、太陽が地平線より下の点は遮られること、
//! 高度が上がるほど遮蔽の境界が下がることを見る。
//!
//! 自己交差の回避を「標本点の半径を縮める」向きに実装すると、余裕より低い高度の点が惑星の内部へ入る。
//! 球の内部から出るレイは向きに関わらず必ず正の遠方交点を持つため、太陽が天頂にあっても遮蔽ありと答える。
//! 既定の観測高度は1.5メートルであり、この誤りは下向き視線の一次散乱の太陽項を一律0にする。

use super::{下端半径, 地球標準の媒体};
use crate::atmosphere::sun_visibility::太陽が地表に遮られるか;
use crate::atmosphere::{位相非対称係数, 地表アルベドRGB, 大気散乱媒体, 消散係数RGB};

/// 惑星中心を原点とし、天頂を+Yに取った座標系での高度から位置を作る。
fn 位置(高度: f64) -> [f64; 3] {
    [0.0, f64::from(下端半径) + 高度, 0.0]
}

/// 天頂余弦から太陽の向きを作る。方位は+X側に取る。
fn 太陽の向き(天頂余弦: f64) -> [f64; 3] {
    [(1.0 - 天頂余弦 * 天頂余弦).max(0.0).sqrt(), 天頂余弦, 0.0]
}

fn 散乱媒体() -> 大気散乱媒体 {
    let [赤, 緑, 青] = super::レイリー散乱係数;
    大気散乱媒体::生成する(
        地球標準の媒体(),
        消散係数RGB::毎メートルから(赤, 緑, 青).unwrap(),
        消散係数RGB::毎メートルから(super::ミー散乱係数, super::ミー散乱係数, super::ミー散乱係数).unwrap(),
        位相非対称係数::生成する(super::位相非対称係数).unwrap(),
        地表アルベドRGB::生成する(0.1, 0.1, 0.1).unwrap(),
    )
    .unwrap()
}

/// 地表すぐ上の点でも、太陽が天頂にあれば遮られない。自己交差の回避が点を惑星の内部へ移すと、
/// この場合に遮蔽ありと答える。既定の観測高度1.5メートルがこの範囲に入る。
#[test]
fn 地表すぐ上の点で天頂の太陽は遮られない() {
    let 媒体 = 散乱媒体();
    let 遮られた高度: Vec<f64> = [0.0_f64, 0.5, 1.0, 1.5, 5.0, 9.9, 30.0]
        .into_iter()
        .filter(|高度| 太陽が地表に遮られるか(&媒体, 位置(*高度), 太陽の向き(1.0)))
        .collect();
    assert!(遮られた高度.is_empty(), "天頂の太陽が遮られた高度がある(メートル): {遮られた高度:?}");
}

/// 太陽が地平線より明確に下にあるときは、高度に関わらず遮られる。自己交差の回避が
/// 「遮蔽ありの側」を削ってしまっていないことの対照である。
#[test]
fn 太陽が地平線より下なら遮られる() {
    let 媒体 = 散乱媒体();
    for 高度 in [0.0_f64, 1.5, 100.0, 10_000.0] {
        for 天頂余弦 in [-1.0_f64, -0.5, -0.2] {
            assert!(
                太陽が地表に遮られるか(&媒体, 位置(高度), 太陽の向き(天頂余弦)),
                "高度{高度}メートルで天頂余弦{天頂余弦}の太陽が遮られなかった"
            );
        }
    }
}

/// 高度が上がると地平線が下がるため、地表では遮られる向きの太陽が高高度では遮られない。
/// 高度10キロメートルの地平線の天頂余弦は約-0.056である。
#[test]
fn 高度が上がると遮蔽の境界が下がる() {
    let 媒体 = 散乱媒体();
    let 天頂余弦 = -0.03;
    assert!(太陽が地表に遮られるか(&媒体, 位置(0.0), 太陽の向き(天頂余弦)));
    assert!(!太陽が地表に遮られるか(&媒体, 位置(10_000.0), 太陽の向き(天頂余弦)));
}
