//! 立方体の面と向きの写像の検査。往復が恒等であること・層番号の並びが規約どおりであること・
//! 隣り合う面の境界が同じ向きを指すことを見る。

use crate::atmosphere::{
    テクセル中心の面内位置, 向きから面と面内位置を求める, 立方体の全面, 立方体の面, 遠方環境の解像度, 面と面内位置から向きを求める,
};

fn 単位化した(向き: [f64; 3]) -> [f64; 3] {
    let 長さ = (向き[0] * 向き[0] + 向き[1] * 向き[1] + 向き[2] * 向き[2]).sqrt();
    [向き[0] / 長さ, 向き[1] / 長さ, 向き[2] / 長さ]
}

/// 層番号は0から5まで重複なく並び、番号からの逆引きが元の面へ戻る。
#[test]
fn 層番号が0から5まで重複なく並ぶ() {
    let 番号一覧: Vec<u32> = 立方体の全面.iter().map(|面| 面.層番号()).collect();
    assert_eq!(番号一覧, vec![0, 1, 2, 3, 4, 5], "層番号の並びが規約と違う");
    for 面 in 立方体の全面 {
        assert_eq!(立方体の面::層番号から求める(面.層番号()).unwrap(), 面, "層番号の逆引きが元へ戻らない");
    }
}

/// 面の中心はその面の主軸そのものを指す。第二軸の正が天頂、第二軸の負が天底である。
#[test]
fn 面の中心が主軸を指す() {
    let 組 = [
        (立方体の面::第一軸の正, [1.0, 0.0, 0.0]),
        (立方体の面::第一軸の負, [-1.0, 0.0, 0.0]),
        (立方体の面::第二軸の正, [0.0, 1.0, 0.0]),
        (立方体の面::第二軸の負, [0.0, -1.0, 0.0]),
        (立方体の面::第三軸の正, [0.0, 0.0, 1.0]),
        (立方体の面::第三軸の負, [0.0, 0.0, -1.0]),
    ];
    for (面, 期待) in 組 {
        let 向き = 面と面内位置から向きを求める(面, 0.5, 0.5);
        for 添字 in 0..3 {
            assert!((向き[添字] - 期待[添字]).abs() < 1.0e-12, "{面:?}の中心が{向き:?}になった");
        }
    }
}

/// 面と面内位置から作った向きを逆写像へ通すと、同じ面と同じ面内位置へ戻る。
#[test]
fn 面と面内位置の往復が恒等である() {
    let 位置一覧 = [0.02_f64, 0.25, 0.5, 0.75, 0.98];
    for 面 in 立方体の全面 {
        for 横位置 in 位置一覧 {
            for 縦位置 in 位置一覧 {
                let 向き = 面と面内位置から向きを求める(面, 横位置, 縦位置);
                let (戻した面, 戻した横, 戻した縦) = 向きから面と面内位置を求める(向き).unwrap();
                assert_eq!(戻した面, 面, "{面:?}が{戻した面:?}へ移った");
                assert!((戻した横 - 横位置).abs() < 1.0e-12, "横{横位置}が{戻した横}になった");
                assert!((戻した縦 - 縦位置).abs() < 1.0e-12, "縦{縦位置}が{戻した縦}になった");
            }
        }
    }
}

/// 隣り合う面の境界のテクセル中心は、半テクセルぶんだけ内側にある2点として、ほぼ同じ向きを指す。
/// 参照する側が面境界で不連続にならない根拠がこれである。
#[test]
fn 面境界の対応するテクセル中心がほぼ同じ向きを指す() {
    let 一辺 = 遠方環境の解像度::既定値().面の一辺();
    let 端 = テクセル中心の面内位置(一辺 - 1, 一辺);
    let 始 = テクセル中心の面内位置(0, 一辺);
    let 中央 = 0.5;
    // 第一軸の正の面の横位置0の端と、第三軸の正の面の横位置1の端は、どちらも第一軸と第三軸がともに正の稜線に接する。
    let 左 = 面と面内位置から向きを求める(立方体の面::第一軸の正, 始, 中央);
    let 右 = 面と面内位置から向きを求める(立方体の面::第三軸の正, 端, 中央);
    let 内積: f64 = 単位化した(左).iter().zip(単位化した(右)).map(|(左値, 右値)| 左値 * 右値).sum();
    let 開き = 内積.clamp(-1.0, 1.0).acos();
    let 一テクセルの角: f64 = 2.0 / f64::from(一辺);
    assert!(
        開き < 一テクセルの角,
        "面境界の2点が{開き}ラジアン開いた(1テクセルぶんは{一テクセルの角})"
    );
}
