//! 空中遠近ボリュームの検査が共有する器。担当するのは、全検査が使う媒体と表と観測条件の組み立てと、
//! 1ボクセルの値を引く入口である。検査そのものは値域・単調性・並びの3つの子モジュールが持つ。
//!
//! 表を焼くのが重いため、各検査が材料を1回組んで使い回す形にまとめる。
//! 解像度を既定の32でなく8に落とすのは、ボクセルごとにカメラから積分し直す形のためボリューム全体の走査が
//! 一辺の4乗に比例し、既定値ではデバッグビルドの検査時間に見合わないからである。写像も積分も一辺に依らないため、
//! 8で成り立つ性質は32でも成り立つ。

mod monotonic_tests;
mod ordering_tests;
mod value_range_tests;

use blitz_math::メートル;

use super::地球標準の媒体;
use crate::atmosphere::{
    位相非対称係数, 単位方向, 地表アルベドRGB, 多重散乱表, 大気LUT解像度, 大気散乱媒体, 消散係数RGB, 空中遠近ボクセル値,
    空中遠近ボリュームのボクセル値, 空中遠近ボリュームの材料, 空中遠近観測条件, 視錐台の向き, 透過率表,
};

/// 検査で使うボリュームの一辺。
pub(super) const 検査の一辺: u32 = 8;
/// 検査で使う最遠距離。地形世界の見える広がり(一辺100メートルのチャンクが5x5)を覆う長さである。
const 検査の最遠距離: f32 = 500.0;

pub(super) struct 材料 {
    媒体: 大気散乱媒体,
    透過率表: 透過率表,
    多重散乱表: 多重散乱表,
    解像度: 大気LUT解像度,
}

pub(super) fn 材料を組む() -> 材料 {
    let 解像度 = 大気LUT解像度::生成する(256, 64, 32, 192, 108, 検査の一辺).unwrap();
    let 媒体 = 大気散乱媒体::生成する(
        地球標準の媒体(),
        消散係数RGB::毎メートルから(super::レイリー散乱係数[0], super::レイリー散乱係数[1], super::レイリー散乱係数[2]).unwrap(),
        消散係数RGB::毎メートルから(super::ミー散乱係数, super::ミー散乱係数, super::ミー散乱係数).unwrap(),
        位相非対称係数::生成する(super::位相非対称係数).unwrap(),
        地表アルベドRGB::生成する(0.1, 0.1, 0.1).unwrap(),
    )
    .unwrap();
    let 透過率表 = 透過率表::焼く(媒体.消散(), 解像度).unwrap();
    let 多重散乱表 = 多重散乱表::焼く(&媒体, &透過率表, 解像度).unwrap();
    材料 {
        媒体,
        透過率表,
        多重散乱表,
        解像度,
    }
}

impl 材料 {
    pub(super) fn 解像度(&self) -> 大気LUT解像度 {
        self.解像度
    }

    pub(super) fn 束にする(&self, 太陽天頂余弦: f32) -> 空中遠近ボリュームの材料<'_> {
        空中遠近ボリュームの材料 {
            媒体: &self.媒体,
            透過率表: &self.透過率表,
            多重散乱表: &self.多重散乱表,
            解像度: self.解像度,
            条件: 条件(太陽天頂余弦),
        }
    }
}

/// 水平方向を正面に取り、視野角90度ぶんを画面の横と縦へ割り当てた視錐台。西から東へ横が伸び、上から下へ縦が伸びる。
fn 検査の視錐台() -> 視錐台の向き {
    視錐台の向き::生成する([-1.0, 1.0, -1.0], [2.0, 0.0, 0.0], [0.0, -2.0, 0.0]).unwrap()
}

/// 太陽を東の空へ置く。天頂余弦から横成分を復元するため、太陽の高度だけを検査が選べる。
fn 条件(太陽天頂余弦: f32) -> 空中遠近観測条件 {
    let 横成分 = (1.0 - 太陽天頂余弦 * 太陽天頂余弦).max(0.0).sqrt();
    空中遠近観測条件::生成する(
        メートル::生成する(1.5),
        単位方向::生成する(横成分, 太陽天頂余弦, 0.0).unwrap(),
        検査の視錐台(),
        メートル::生成する(検査の最遠距離),
    )
    .unwrap()
}

pub(super) fn ボクセル(材料: &材料, 太陽天頂余弦: f32, 横: u32, 縦: u32, 奥: u32) -> 空中遠近ボクセル値 {
    空中遠近ボリュームのボクセル値(材料.束にする(太陽天頂余弦), 横, 縦, 奥).unwrap()
}

/// 画面の隅と中央を代表として選ぶ。写像が横縦を扱う端と真ん中を1つずつ覆う。
pub(super) fn 代表の画面位置() -> [(u32, u32); 3] {
    [(0, 0), (検査の一辺 / 2, 検査の一辺 / 2), (検査の一辺 - 1, 検査の一辺 - 1)]
}
