//! 参照データの本文を1行ずつレコードへ読み解く工程。受け取るのは本文、返すのはレコードの一覧である。
//!
//! 読めない行を黙って飛ばさないのは、参照データの形式が変わったときに検査が「レコード0件で全部通る」
//! という状態へ静かに落ちるのを防ぐためである。読めない行はその場で失敗させる。

use super::reference_record::参照レコード;

pub(super) fn 読み解く(本文: &str) -> Vec<参照レコード> {
    let mut 一覧 = Vec::new();
    for (行番号, 行) in 本文.lines().enumerate() {
        let 整形済み = 行.trim();
        if 整形済み.is_empty() || 整形済み.starts_with('#') {
            continue;
        }
        一覧.push(レコードを読む(整形済み).unwrap_or_else(|| panic!("参照データの{}行目を読めない: {整形済み}", 行番号 + 1)));
    }
    assert!(!一覧.is_empty(), "参照データにレコードが1件も無い");
    一覧
}

fn レコードを読む(行: &str) -> Option<参照レコード> {
    let mut 語 = 行.split_whitespace();
    let 種別 = 語.next()?;
    if 種別 == "param" {
        let 名前 = 語.next()?.to_string();
        return Some(参照レコード::パラメータ {
            名前, 値: 数(語.next())?
        });
    }
    let 数値: Option<Vec<f64>> = 語.map(|語| 語.parse::<f64>().ok()).collect();
    let 数値 = 数値?;
    match (種別, 数値.len()) {
        ("density", 4) => Some(参照レコード::密度 {
            高度: 数値[0],
            レイリー: 数値[1],
            ミー: 数値[2],
            吸収: 数値[3],
        }),
        ("horizon", 2) => Some(参照レコード::地平線 {
            半径: 数値[0],
            天頂余弦: 数値[1],
        }),
        ("top_distance", 3) => Some(参照レコード::上端距離 {
            半径: 数値[0],
            天頂余弦: 数値[1],
            距離: 数値[2],
        }),
        ("bottom_distance", 3) => Some(参照レコード::地表距離 {
            半径: 数値[0],
            天頂余弦: 数値[1],
            距離: 数値[2],
        }),
        ("optical_length", 5) => Some(参照レコード::光学距離 {
            半径: 数値[0],
            天頂余弦: 数値[1],
            レイリー: 数値[2],
            ミー: 数値[3],
            吸収: 数値[4],
        }),
        ("transmittance", 5) => Some(参照レコード::透過率 {
            半径: 数値[0],
            天頂余弦: 数値[1],
            成分: [数値[2], 数値[3], 数値[4]],
        }),
        ("phase", 3) => Some(参照レコード::位相 {
            散乱角余弦: 数値[0],
            レイリー: 数値[1],
            ミー: 数値[2],
        }),
        _ => None,
    }
}

fn 数(語: Option<&str>) -> Option<f64> {
    語?.parse::<f64>().ok()
}
