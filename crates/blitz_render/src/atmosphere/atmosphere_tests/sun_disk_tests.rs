//! 太陽円盤の画素に掛かる透過率の検査。円盤が地平線をまたぐとき下側の画素だけが消えること、
//! 円盤の中でも画素ごとに減光が違うこと、天頂へ向かう画素が最も減らないことを見る。
//!
//! 旧実装は円盤の中心方向で透過率を1つ引き、惑星の遮蔽も中心の天頂角と地平線の天頂角のsmoothstepで作っていた。
//! その形では円盤の全画素が同じ値を取るため、1つ目と2つ目の検査が落ちる。

use blitz_math::メートル;

use super::{下端半径, 地球標準の媒体};
use crate::atmosphere::sun_visibility::太陽円盤の画素に掛かる透過率を求める;
use crate::atmosphere::{地平線の天頂余弦, 大気LUT解像度, 大気内観測点, 天頂余弦, 消散媒体, 透過率表};

/// 太陽円盤の角半径。空描画方針の既定値0.27度に相当する。
const 太陽の角半径: f32 = 0.004_712;

/// 空描画方針の既定の観測高度。この高度の地平線の天頂余弦は約-6.9e-4で太陽の角半径より小さいため、
/// 太陽の中心が地平線にある時刻に円盤が地平線をまたぐ。
const 観測高度: f32 = 1.5;

fn 表を焼く(媒体: &消散媒体) -> 透過率表 {
    透過率表::焼く(媒体, 大気LUT解像度::既定値()).unwrap()
}

fn 観測点(媒体: &消散媒体) -> 大気内観測点<'_> {
    大気内観測点::生成する(媒体, メートル::生成する(下端半径 + 観測高度)).unwrap()
}

/// 画素1つぶんの透過率。検査が視線の天頂余弦だけを動かすため、生値から値オブジェクトへの包みをここへ寄せる。
fn 画素の透過率(観測点: 大気内観測点<'_>, 表: &透過率表, 視線天頂余弦: f32) -> [f32; 3] {
    太陽円盤の画素に掛かる透過率を求める(観測点, 天頂余弦::生成する(視線天頂余弦).unwrap(), 表).成分()
}

/// 円盤の中心を地平線に置くと、上側の画素は大気上端へ抜けて減光だけを受け、下側の画素は惑星に入って消える。
#[test]
fn 地平線をまたぐ円盤は上側だけが残る() {
    let 媒体 = 地球標準の媒体();
    let 表 = 表を焼く(&媒体);
    let 観測点 = 観測点(&媒体);
    let 円盤中心 = 地平線の天頂余弦(観測点).値();
    let 上側 = 画素の透過率(観測点, &表, 円盤中心 + 太陽の角半径 * 0.5);
    let 下側 = 画素の透過率(観測点, &表, 円盤中心 - 太陽の角半径 * 0.5);
    assert!(上側.iter().all(|値| *値 > 0.0), "円盤の上側の画素が消えた: {上側:?}");
    assert_eq!(下側, [0.0, 0.0, 0.0], "円盤の下側の画素が残った");
}

/// 円盤が地平線より上にあるときも、下寄りの画素は上寄りの画素より長い経路を通るため減光が強い。
/// 中心方向で1つの値を引く形では両者が一致する。
#[test]
fn 円盤の中でも画素ごとに減光が違う() {
    let 媒体 = 地球標準の媒体();
    let 表 = 表を焼く(&媒体);
    let 観測点 = 観測点(&媒体);
    let 円盤中心 = 地平線の天頂余弦(観測点).値() + 太陽の角半径 * 2.0;
    let 上端 = 画素の透過率(観測点, &表, 円盤中心 + 太陽の角半径);
    let 下端 = 画素の透過率(観測点, &表, 円盤中心 - 太陽の角半径);
    for (上, 下) in 上端.into_iter().zip(下端) {
        assert!(下 < 上, "円盤の下端の透過率{下}が上端の{上}より減っていない");
    }
}

/// 天頂へ向かう画素の透過率が最も大きい。視線が寝るほど経路が伸びて減るという単調性の対照である。
#[test]
fn 天頂へ向かう画素が最も減らない() {
    let 媒体 = 地球標準の媒体();
    let 表 = 表を焼く(&媒体);
    let 観測点 = 観測点(&媒体);
    let 天頂 = 画素の透過率(観測点, &表, 1.0);
    let 斜め = 画素の透過率(観測点, &表, 0.2);
    for (真上, 傾き) in 天頂.into_iter().zip(斜め) {
        assert!(真上 > 傾き, "天頂の透過率{真上}が傾いた視線の{傾き}より小さい");
    }
}
