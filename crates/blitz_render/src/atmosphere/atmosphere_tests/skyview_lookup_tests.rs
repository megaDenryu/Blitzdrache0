//! スカイビューLUTを引く側の写像の検査。方位余弦が水平面の相対方位を表すこと・天頂と天底で方位が決まらない場合の
//! 扱い・焼く側の写像との往復を見る。

use super::地球標準の媒体;
use crate::atmosphere::{
    スカイビューlutの単位位置を求める, スカイビューlutの視線を求める, ワールドの視線からスカイビューlutの視線を求める
};

/// 東を+X、天頂を+Y、南を+Zに取ったワールドで、南東の空に太陽がある向き。
fn 太陽方向() -> [f64; 3] {
    let 水平 = (0.5_f64).sqrt();
    [水平 * 0.6, 0.8, 水平 * 0.6]
}

fn 単位化した(向き: [f64; 3]) -> [f64; 3] {
    let 長さ = (向き[0] * 向き[0] + 向き[1] * 向き[1] + 向き[2] * 向き[2]).sqrt();
    [向き[0] / 長さ, 向き[1] / 長さ, 向き[2] / 長さ]
}

/// 視線の天頂余弦がワールドのY成分そのものである。
#[test]
fn 天頂余弦がy成分である() {
    for y in [-1.0_f64, -0.3, 0.0, 0.4, 1.0] {
        let 水平 = (1.0 - y * y).max(0.0).sqrt();
        let 視線 = ワールドの視線からスカイビューlutの視線を求める([水平, y, 0.0], 太陽方向()).unwrap();
        let 差 = f64::from(視線.視線天頂余弦.値()) - y;
        assert!(差.abs() < 1.0e-6, "y{y}が{}になった", 視線.視線天頂余弦.値());
    }
}

/// 太陽と同じ方位を向く視線は方位余弦1、反対の方位は-1、真横は0になる。天頂角は方位余弦へ影響しない。
#[test]
fn 方位余弦が水平面の相対方位を表す() {
    let 太陽 = 単位化した(太陽方向());
    let 太陽の水平 = 単位化した([太陽[0], 0.0, 太陽[2]]);
    let 同じ方位 = 単位化した([太陽の水平[0], 2.0, 太陽の水平[2]]);
    let 反対方位 = 単位化した([-太陽の水平[0], 0.3, -太陽の水平[2]]);
    let 真横 = 単位化した([-太陽の水平[2], 0.1, 太陽の水平[0]]);
    let 組 = [(同じ方位, 1.0_f32), (反対方位, -1.0), (真横, 0.0)];
    for (視線, 期待) in 組 {
        let 求めた = ワールドの視線からスカイビューlutの視線を求める(視線, 太陽).unwrap();
        assert!(
            (求めた.太陽方位余弦.値() - 期待).abs() < 1.0e-5,
            "期待{期待}に対して{}",
            求めた.太陽方位余弦.値()
        );
    }
}

/// 天頂を向く視線と天底を向く視線は水平成分を持たないため、方位余弦を太陽と同じ方位として扱う。
/// LUTの縦0と縦1の行はどの横位置でも同じ値であるため、この選び方で引く値は変わらない。
#[test]
fn 天頂と天底では方位を太陽の側に置く() {
    for y in [1.0_f64, -1.0] {
        let 視線 = ワールドの視線からスカイビューlutの視線を求める([0.0, y, 0.0], 太陽方向()).unwrap();
        assert!((視線.太陽方位余弦.値() - 1.0).abs() < 1.0e-6, "{}", 視線.太陽方位余弦.値());
    }
}

/// 方位を決められるかは水平成分のユークリッドの長さで決める。成分の絶対値の和で測ると、和が下限を超えるのに
/// 長さが下限を割る向きを「決められる」と扱い、`length`で測るslang写しと答えが分かれる。
#[test]
fn 方位の可否は水平成分のユークリッドの長さで決める() {
    let 太陽 = 単位化した(太陽方向());
    let 太陽の水平 = 単位化した([太陽[0], 0.0, 太陽[2]]);
    // 水平成分の長さ8.5e-7は下限1.0e-6を割るが、成分の絶対値の和は1.2e-6で下限を超える。
    let 視線 = [-太陽の水平[0] * 8.5e-7, -1.0, -太陽の水平[2] * 8.5e-7];
    let 余弦 = ワールドの視線からスカイビューlutの視線を求める(視線, 太陽).unwrap().太陽方位余弦.値();
    assert!((余弦 - 1.0).abs() < 1.0e-6, "方位を決められない向きなのに{余弦}を返した");
}

/// 太陽が天頂にあるときも方位を決められない。球対称の大気ではどの方位から見ても同じ表になる。
#[test]
fn 太陽が天頂にあるときも方位を太陽の側に置く() {
    let 視線 = ワールドの視線からスカイビューlutの視線を求める(単位化した([1.0, 0.2, 0.5]), [0.0, 1.0, 0.0]).unwrap();
    assert!((視線.太陽方位余弦.値() - 1.0).abs() < 1.0e-6, "{}", 視線.太陽方位余弦.値());
}

/// 引く側の視線を焼く側の単位位置へ写し、その単位位置から焼く側が復元する視線と一致する。
/// 焼いた座標と引く座標が同じ点を指すことがこの往復で保たれる。
#[test]
fn 焼く側の写像と往復する() {
    let 媒体 = 地球標準の媒体();
    let 半径 = f64::from(super::下端半径) + 1.5;
    let 太陽 = 単位化した(太陽方向());
    for 段 in 0..8 {
        let 方位角 = std::f64::consts::TAU * f64::from(段) / 8.0;
        for y in [-0.5_f64, -0.02, 0.1, 0.7] {
            let 水平 = (1.0 - y * y).max(0.0).sqrt();
            let 視線 = [水平 * 方位角.cos(), y, 水平 * 方位角.sin()];
            let 引く視線 = ワールドの視線からスカイビューlutの視線を求める(視線, 太陽).unwrap();
            let [横, 縦] = スカイビューlutの単位位置を求める(&媒体, 半径, 引く視線);
            let 戻り = スカイビューlutの視線を求める(&媒体, 半径, 横, 縦).unwrap();
            let 天頂差 = 戻り.視線天頂余弦.値() - 引く視線.視線天頂余弦.値();
            let 方位差 = 戻り.太陽方位余弦.値() - 引く視線.太陽方位余弦.値();
            assert!(天頂差.abs() < 1.0e-4, "天頂余弦が{天頂差}ずれた");
            assert!(方位差.abs() < 1.0e-4, "方位余弦が{方位差}ずれた");
        }
    }
}
