//! 透過率LUTの写像と焼いた値の検査。写像の往復・軸の意味・値域・上端での透明さを見る。

use super::地球標準の媒体;
use crate::atmosphere::{
    テクセル中心のuv, 大気LUT解像度, 大気内観測点, 天頂余弦, 透過率lutのuvを求める, 透過率lutのテクセル値, 透過率lutの視線を求める,
};
use blitz_math::メートル;

fn 解像度() -> 大気LUT解像度 {
    大気LUT解像度::既定値()
}

/// 写像とその逆写像の往復でテクセル中心のUVへ戻る。往復がずれると焼いた座標と引く座標が食い違う。
///
/// 許容を5e-4(0.13テクセル)にするのは、往復の途中で半径がf32へ狭まるためである。地表付近の半径6.36e6メートルは
/// f32では0.5メートル刻みでしか表せず、そこから地表からの弦を取り直すと横軸の位置が数万分の1だけ動く。
/// 本番のLUTは前向きの写像しか通らず、逆写像には幾何から来た半径を渡すため、この誤差は絵に出ない。
#[test]
fn 写像と逆写像がテクセル中心へ戻る() {
    let 媒体 = 地球標準の媒体();
    let 解像度 = 解像度();
    for 縦 in [0, 1, 17, 63] {
        for 横 in [0, 1, 128, 255] {
            let 横uv = テクセル中心のuv(横, 解像度.透過率の幅());
            let 縦uv = テクセル中心のuv(縦, 解像度.透過率の高さ());
            let 視線 = 透過率lutの視線を求める(&媒体, 横uv, 縦uv).unwrap();
            let [戻り横, 戻り縦] = 透過率lutのuvを求める(視線.観測点, 視線.天頂余弦);
            assert!((戻り横 - 横uv).abs() < 5e-4, "横{横}縦{縦}のuv横が{横uv}から{戻り横}へずれた");
            assert!((戻り縦 - 縦uv).abs() < 5e-4, "横{横}縦{縦}のuv縦が{縦uv}から{戻り縦}へずれた");
        }
    }
}

/// 縦軸は観測点の高さである。下端の行が地表付近、上端の行が大気上端付近を表す。
#[test]
fn 縦軸が観測点の高さを表す() {
    let 媒体 = 地球標準の媒体();
    let 解像度 = 解像度();
    let 最下行 = 透過率lutの視線を求める(&媒体, 0.5, テクセル中心のuv(0, 解像度.透過率の高さ())).unwrap();
    let 最上行 = 透過率lutの視線を求める(&媒体, 0.5, テクセル中心のuv(63, 解像度.透過率の高さ())).unwrap();
    assert!(最下行.観測点.高度().値() < 100.0, "最下行の高度が{}", 最下行.観測点.高度().値());
    // 最上行のテクセル中心は63.5/64であり、上端そのものではないため厚み10万メートルのうち98パーセント強までを表す。
    assert!(最上行.観測点.高度().値() > 98_000.0, "最上行の高度が{}", 最上行.観測点.高度().値());
}

/// 横軸は大気上端までの距離である。左端が最短(真上向き)、右端が最長(地平線方向)になる。
#[test]
fn 横軸の左端が真上で右端が地平線を向く() {
    let 媒体 = 地球標準の媒体();
    let 解像度 = 解像度();
    let 縦uv = テクセル中心のuv(32, 解像度.透過率の高さ());
    let 左端 = 透過率lutの視線を求める(&媒体, テクセル中心のuv(0, 解像度.透過率の幅()), 縦uv).unwrap();
    let 右端 = 透過率lutの視線を求める(&媒体, テクセル中心のuv(255, 解像度.透過率の幅()), 縦uv).unwrap();
    // 左端のテクセル中心も0.5/256だけ内側にあるため、真上ちょうど(余弦1)にはならない。
    assert!(左端.天頂余弦.値() > 0.95, "左端の天頂余弦が{}", 左端.天頂余弦.値());
    assert!(右端.天頂余弦.値() < 左端.天頂余弦.値());
    let 地平線 = crate::atmosphere::地平線の天頂余弦(右端.観測点);
    assert!(右端.天頂余弦.値() >= 地平線.値() - 1e-3, "右端が地平線より下を向いた");
}

/// 焼いた値は0以上1以下で有限であり、真上を向く視線ほど透過率が高い。
#[test]
fn 焼いた透過率が値域に収まり真上ほど明るい() {
    let 媒体 = 地球標準の媒体();
    let 解像度 = 解像度();
    let 真上 = 透過率lutのテクセル値(&媒体, 解像度, 0, 0).unwrap().成分();
    let 地平線側 = 透過率lutのテクセル値(&媒体, 解像度, 255, 0).unwrap().成分();
    for (真上成分, 地平線成分) in 真上.into_iter().zip(地平線側) {
        assert!((0.0..=1.0).contains(&真上成分) && 真上成分.is_finite());
        assert!((0.0..=1.0).contains(&地平線成分) && 地平線成分.is_finite());
        assert!(真上成分 > 地平線成分, "真上{真上成分}が地平線側{地平線成分}より暗い");
    }
}

/// 大気上端から真上を向く視線は媒体をほとんど通らないため、ほぼ完全に透明になる。
#[test]
fn 大気上端から真上を向く視線はほぼ透明である() {
    let 媒体 = 地球標準の媒体();
    let 観測点 = 大気内観測点::生成する(&媒体, メートル::生成する(6_460_000.0)).unwrap();
    let [横, 縦] = 透過率lutのuvを求める(観測点, 天頂余弦::生成する(1.0).unwrap());
    assert!(横.abs() < 1e-3 && (縦 - 1.0).abs() < 1e-3, "上端の真上がuv({横}, {縦})へ写った");
}
