//! 光学距離の検査。垂直方向の閉形式との一致、区間数を増やしたときの誤差の減り方、視線の傾きに対する単調性を見る。

use super::super::{上端までの光学距離, 大気内観測点, 天頂余弦, 積分標本数};
use super::{m, レイリー尺度高度, 上端半径, 下端半径, 地球標準の媒体};

/// 尺度高度Hの指数分布を地表から真上へ厚みTだけ積分した閉形式は`H * (1 - exp(-T / H))`である。
fn 垂直の閉形式() -> f64 {
    let 尺度高度 = f64::from(レイリー尺度高度);
    let 厚み = f64::from(上端半径 - 下端半径);
    尺度高度 * (1.0 - (-厚み / 尺度高度).exp())
}

fn 垂直の光学距離(区間数: u32) -> f64 {
    let 媒体 = 地球標準の媒体();
    let 観測点 = 大気内観測点::生成する(&媒体, m(下端半径)).unwrap();
    let 積分 = 上端までの光学距離(
        観測点,
        &媒体.レイリー().密度分布(),
        天頂余弦::生成する(1.0).unwrap(),
        積分標本数::生成する(区間数).unwrap(),
    );
    f64::from(積分.値())
}

/// 実測は閉形式が7999.9701867746、区間数20000の積分が7999.9702148438であり、相対誤差は3.5e-9である。
/// 判定をこの実測値へ張り付けないのは、原理的な下限が2つあるためである。台形則の相対誤差は刻み幅の2乗に
/// 比例し、この条件では3.3e-8まで下がる。f32が8000付近で表せる刻みは半ulpで相対3.1e-8である。
/// この2つの和6.4e-8を下回る閾値は、実装が正しくても再現しない可能性がある。判定はその3倍の2e-7を上限とする。
#[test]
fn 垂直の光学距離が閉形式と一致する() {
    let 期待 = 垂直の閉形式();
    let 実測 = 垂直の光学距離(20_000);
    let 相対誤差 = (実測 - 期待).abs() / 期待;
    assert!(相対誤差 < 2e-7, "相対誤差{相対誤差}、実測{実測}、閉形式{期待}");
}

/// 台形則の誤差は刻み幅の2乗に比例するため、区間数を2倍にすると誤差はおよそ4分の1になる。
/// 誤差が縮まらなければ、積分が台形則になっていないか閉形式が誤っている。
#[test]
fn 区間数を倍にすると誤差がおよそ4分の1になる() {
    let 期待 = 垂直の閉形式();
    let 粗い誤差 = (垂直の光学距離(250) - 期待).abs();
    let 細かい誤差 = (垂直の光学距離(500) - 期待).abs();
    let 比 = 粗い誤差 / 細かい誤差;
    assert!((3.5..=4.5).contains(&比), "誤差比{比}、粗い{粗い誤差}、細かい{細かい誤差}");
}

/// 密度は1以下であるため、光学距離は同じ経路の幾何的な長さを超えない。
#[test]
fn 光学距離は幾何距離を超えない() {
    let 媒体 = 地球標準の媒体();
    let 標本数 = 積分標本数::生成する(500).unwrap();
    for 高度 in [0.0_f32, 10_000.0, 50_000.0] {
        let 観測点 = 大気内観測点::生成する(&媒体, m(下端半径 + 高度)).unwrap();
        for mu in [0.05_f32, 0.3, 0.7, 1.0] {
            let 余弦 = 天頂余弦::生成する(mu).unwrap();
            let 幾何 = super::super::大気上端までの距離(観測点, 余弦).値();
            let 光学 = 上端までの光学距離(観測点, &媒体.レイリー().密度分布(), 余弦, 標本数).値();
            assert!(光学 <= 幾何, "高度{高度}のmu={mu}で光学{光学}が幾何{幾何}を超えた");
        }
    }
}

/// 視線を寝かせるほど大気を長く通るため、光学距離は天頂余弦に対して単調に減らない。
#[test]
fn 視線を寝かせるほど光学距離が増える() {
    let 媒体 = 地球標準の媒体();
    let 観測点 = 大気内観測点::生成する(&媒体, m(下端半径)).unwrap();
    let 標本数 = 積分標本数::生成する(2000).unwrap();
    let mut 前 = f32::MAX;
    for 段 in 0..=20u8 {
        let mu = f32::from(段) / 20.0;
        let 余弦 = 天頂余弦::生成する(mu).unwrap();
        let 値 = 上端までの光学距離(観測点, &媒体.レイリー().密度分布(), 余弦, 標本数).値();
        assert!(値 <= 前, "mu={mu}で光学距離が増えた");
        前 = 値;
    }
}
