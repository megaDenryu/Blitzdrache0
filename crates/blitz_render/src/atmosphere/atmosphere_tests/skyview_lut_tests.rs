//! スカイビューLUTが焼く値の検査。値域・太陽の側が明るいこと・太陽が沈むと暗くなること・
//! 地面を向く向きが空より暗いこと・決定性を見る。焼くのに時間がかかるため代表テクセルだけを求める。

use blitz_math::メートル;

use super::地球標準の媒体;
use crate::atmosphere::{
    スカイビューlutのテクセル値, スカイビュー観測条件, 位相非対称係数, 地表アルベドRGB, 多重散乱表, 大気LUT解像度, 大気散乱媒体, 天頂余弦,
    消散係数RGB, 透過率表,
};

/// 表を焼くのが重いため、1回組んだ材料を各検査が使い回す形にまとめる。
struct 材料 {
    媒体: 大気散乱媒体,
    透過率表: 透過率表,
    多重散乱表: 多重散乱表,
    解像度: 大気LUT解像度,
}

fn 材料を組む() -> 材料 {
    let 解像度 = 大気LUT解像度::既定値();
    let 媒体 = 大気散乱媒体::生成する(
        地球標準の媒体(),
        消散係数RGB::毎メートルから(super::レイリー散乱係数[0], super::レイリー散乱係数[1], super::レイリー散乱係数[2]).unwrap(),
        消散係数RGB::毎メートルから(super::ミー散乱係数, super::ミー散乱係数, super::ミー散乱係数).unwrap(),
        位相非対称係数::生成する(super::位相非対称係数).unwrap(),
        地表アルベドRGB::生成する(0.1, 0.1, 0.1).unwrap(),
    )
    .unwrap();
    let 透過率表 = 透過率表::焼く(媒体.消散(), 解像度).unwrap();
    let 多重散乱表 = 多重散乱表::焼く(&媒体, &透過率表, 解像度).unwrap();
    材料 {
        媒体,
        透過率表,
        多重散乱表,
        解像度,
    }
}

fn 条件(太陽天頂余弦: f32) -> スカイビュー観測条件 {
    スカイビュー観測条件::生成する(メートル::生成する(1.5), 天頂余弦::生成する(太陽天頂余弦).unwrap()).unwrap()
}

fn テクセル(材料: &材料, 太陽天頂余弦: f32, 横: u32, 縦: u32) -> [f32; 3] {
    スカイビューlutのテクセル値(&材料.媒体, &材料.透過率表, &材料.多重散乱表, 材料.解像度, 条件(太陽天頂余弦), 横, 縦)
        .unwrap()
        .成分()
}

/// 全ての代表テクセルが有限かつ非負である。
#[test]
fn 代表テクセルが有限かつ非負である() {
    let 材料 = 材料を組む();
    for (横, 縦) in [(0, 0), (95, 0), (191, 0), (0, 53), (95, 53), (191, 107)] {
        for 値 in テクセル(&材料, 0.6, 横, 縦) {
            assert!(値.is_finite() && 値 >= 0.0, "横{横}縦{縦}の成分が{値}");
        }
    }
}

/// 太陽が真上に近い正午の空は、同じ向きを見た夜より明るい。太陽が地平線の下では散乱の源が無くなる。
#[test]
fn 太陽が沈むと空が暗くなる() {
    let 材料 = 材料を組む();
    let 昼 = テクセル(&材料, 0.95, 96, 20);
    let 夜 = テクセル(&材料, -0.3, 96, 20);
    for (昼値, 夜値) in 昼.into_iter().zip(夜) {
        assert!(昼値 > 夜値, "昼{昼値}に対して夜{夜値}");
        assert!(夜値 >= 0.0, "夜が{夜値}");
    }
}

/// 太陽高度が低いとき、太陽と同じ方位の空は反対の方位の空より明るい(前方散乱の偏り)。
#[test]
fn 太陽の側の空が反対側より明るい() {
    let 材料 = 材料を組む();
    let 太陽側 = テクセル(&材料, 0.2, 0, 40);
    let 反対側 = テクセル(&材料, 0.2, 191, 40);
    let 太陽側の和: f32 = 太陽側.iter().sum();
    let 反対側の和: f32 = 反対側.iter().sum();
    assert!(太陽側の和 > 反対側の和, "太陽側{太陽側の和}に対して反対側{反対側の和}");
}

/// 天頂を見た昼の空は、青が赤より明るい(レイリー散乱の波長依存)。
#[test]
fn 天頂の空は青が赤より明るい() {
    let 材料 = 材料を組む();
    let [赤, _, 青] = テクセル(&材料, 0.95, 96, 0);
    assert!(青 > 赤 * 2.0, "赤{赤}に対して青{青}");
}

/// 同じ入力を2回焼くと完全に一致する。履歴も乱数も持たないことの検査である。
#[test]
fn 同じ入力を2回焼くと完全に一致する() {
    let 材料 = 材料を組む();
    assert_eq!(テクセル(&材料, 0.4, 30, 60), テクセル(&材料, 0.4, 30, 60));
}
