//! 多重散乱LUTの写像と焼いた値の検査。軸の意味・値域・太陽が高いほど明るいこと・地表アルベドへの単調性を見る。
//! 焼くのに時間がかかるため、全テクセルでなく代表テクセルだけを求める。

use super::地球標準の媒体;
use crate::atmosphere::{
    位相非対称係数, 地表アルベドRGB, 多重散乱lutのテクセル値, 多重散乱lutの条件を求める, 大気LUT解像度, 大気散乱媒体, 消散係数RGB, 透過率表,
};

fn 解像度() -> 大気LUT解像度 {
    大気LUT解像度::既定値()
}

fn 散乱媒体(地表アルベド: f32) -> 大気散乱媒体 {
    大気散乱媒体::生成する(
        地球標準の媒体(),
        消散係数RGB::毎メートルから(super::レイリー散乱係数[0], super::レイリー散乱係数[1], super::レイリー散乱係数[2]).unwrap(),
        消散係数RGB::毎メートルから(super::ミー散乱係数, super::ミー散乱係数, super::ミー散乱係数).unwrap(),
        位相非対称係数::生成する(super::位相非対称係数).unwrap(),
        地表アルベドRGB::生成する(地表アルベド, 地表アルベド, 地表アルベド).unwrap(),
    )
    .unwrap()
}

/// 横軸は太陽の天頂余弦であり、左端が真下(-1)、右端が真上(+1)を表す。縦軸は観測点の高さである。
#[test]
fn 軸の両端が太陽の向きと高さの端を表す() {
    let 媒体 = 地球標準の媒体();
    let 解像度 = 解像度();
    let 左下 = 多重散乱lutの条件を求める(&媒体, 解像度, 0, 0).unwrap();
    let 右上 = 多重散乱lutの条件を求める(&媒体, 解像度, 31, 31).unwrap();
    assert!((左下.太陽天頂余弦.値() + 1.0).abs() < 1e-6);
    assert!((右上.太陽天頂余弦.値() - 1.0).abs() < 1e-6);
    // 最下行は地表から大気の厚みの1パーセント、最上行は大気上端から10メートル内側に置く(端点の経路長が0になるのを避けるため)。
    assert!((左下.半径.値() - 6_360_999.9).abs() < 10.0, "最下行の半径が{}", 左下.半径.値());
    assert!((右上.半径.値() - 6_459_990.0).abs() < 10.0, "最上行の半径が{}", 右上.半径.値());
}

/// 焼いた値は有限かつ非負であり、太陽が真上のほうが真下より明るい。
#[test]
fn 太陽が真上のほうが真下より明るい() {
    let 媒体 = 散乱媒体(0.1);
    let 解像度 = 解像度();
    let 表 = 透過率表::焼く(媒体.消散(), 解像度).unwrap();
    let 真下 = 多重散乱lutのテクセル値(&媒体, &表, 解像度, 0, 0).unwrap().成分();
    let 真上 = 多重散乱lutのテクセル値(&媒体, &表, 解像度, 31, 0).unwrap().成分();
    for (下, 上) in 真下.into_iter().zip(真上) {
        assert!(下.is_finite() && 下 >= 0.0, "真下が{下}");
        assert!(上.is_finite() && 上 >= 0.0, "真上が{上}");
        assert!(上 > 下, "太陽が真上のとき{上}で真下のとき{下}");
    }
}

/// 地表アルベドを上げると地面からの照り返しが増え、多重散乱も増える。
#[test]
fn 地表の反射率を上げると多重散乱が増える() {
    let 解像度 = 解像度();
    let 暗い地面 = 散乱媒体(0.05);
    let 明るい地面 = 散乱媒体(0.4);
    let 暗い表 = 透過率表::焼く(暗い地面.消散(), 解像度).unwrap();
    let 明るい表 = 透過率表::焼く(明るい地面.消散(), 解像度).unwrap();
    let 暗い値 = 多重散乱lutのテクセル値(&暗い地面, &暗い表, 解像度, 24, 0).unwrap().成分();
    let 明るい値 = 多重散乱lutのテクセル値(&明るい地面, &明るい表, 解像度, 24, 0).unwrap().成分();
    for (暗い, 明るい) in 暗い値.into_iter().zip(明るい値) {
        assert!(明るい > 暗い, "反射率0.4で{明るい}、0.05で{暗い}");
    }
}

/// 同じ入力を2回焼くと完全に一致する。履歴も乱数も持たないことの検査である。
#[test]
fn 同じ入力を2回焼くと完全に一致する() {
    let 媒体 = 散乱媒体(0.1);
    let 解像度 = 解像度();
    let 表 = 透過率表::焼く(媒体.消散(), 解像度).unwrap();
    let 一回目 = 多重散乱lutのテクセル値(&媒体, &表, 解像度, 20, 12).unwrap();
    let 二回目 = 多重散乱lutのテクセル値(&媒体, &表, 解像度, 20, 12).unwrap();
    assert_eq!(一回目.成分(), 二回目.成分());
}
