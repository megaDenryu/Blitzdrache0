//! 透過率の検査。値域、経路長に対する単調性、決定性、全出力の有限性を見る。

use super::super::{上端までの光学距離, 上端までの透過率, 大気内半径, 天頂余弦, 積分標本数};
use super::{m, 下端半径, 地球標準の媒体};

fn 標本数() -> 積分標本数 {
    積分標本数::生成する(500).unwrap()
}

#[test]
fn 透過率は0以上1以下の有限値になる() {
    let 媒体 = 地球標準の媒体();
    for 高度段 in 0..=100u8 {
        let 半径 = 大気内半径::生成する(&媒体, m(下端半径 + f32::from(高度段) * 1000.0)).unwrap();
        for mu段 in 0..=40u8 {
            let 余弦 = 天頂余弦::生成する(f32::from(mu段) / 40.0).unwrap();
            for 成分 in 上端までの透過率(&媒体, 半径, 余弦, 標本数()).成分() {
                assert!(成分.is_finite() && (0.0..=1.0).contains(&成分), "高度{高度段}kmのmu段{mu段}で{成分}");
            }
        }
    }
}

/// 視線を寝かせるほど経路が長くなり、光学的深さが増えるため透過率は減る。
#[test]
fn 視線を寝かせるほど透過率が減る() {
    let 媒体 = 地球標準の媒体();
    let 半径 = 大気内半径::生成する(&媒体, m(下端半径)).unwrap();
    let mut 前 = [0.0_f32; 3];
    for 段 in 0..=40u8 {
        let 余弦 = 天頂余弦::生成する(f32::from(段) / 40.0).unwrap();
        let 成分 = 上端までの透過率(&媒体, 半径, 余弦, 標本数()).成分();
        for 添字 in 0..3 {
            assert!(成分[添字] >= 前[添字], "mu段{段}のチャネル{添字}で透過率が減った");
        }
        前 = 成分;
    }
}

/// 高度が上がるほど頭上に残る大気が減るため、真上への透過率は増える。
#[test]
fn 高度が上がるほど真上への透過率が増える() {
    let 媒体 = 地球標準の媒体();
    let 余弦 = 天頂余弦::生成する(1.0).unwrap();
    let mut 前 = [0.0_f32; 3];
    for 段 in 0..=100u8 {
        let 半径 = 大気内半径::生成する(&媒体, m(下端半径 + f32::from(段) * 1000.0)).unwrap();
        let 成分 = 上端までの透過率(&媒体, 半径, 余弦, 標本数()).成分();
        for 添字 in 0..3 {
            assert!(成分[添字] >= 前[添字], "高度{段}kmのチャネル{添字}で透過率が減った");
        }
        前 = 成分;
    }
}

/// 大気の上端では通る大気が無いため透過率は1に等しい。
#[test]
fn 上端では透過率が1になる() {
    let 媒体 = 地球標準の媒体();
    let 半径 = 大気内半径::生成する(&媒体, 媒体.上端半径()).unwrap();
    let 成分 = 上端までの透過率(&媒体, 半径, 天頂余弦::生成する(1.0).unwrap(), 標本数()).成分();
    for 値 in 成分 {
        assert!((値 - 1.0).abs() < 1e-6, "{値}");
    }
}

/// 履歴も乱数も持たない純関数であるため、同じ入力からは同じビットの出力が得られる。
#[test]
fn 同じ入力を2回評価すると完全に一致する() {
    let 媒体 = 地球標準の媒体();
    for 高度 in [0.0_f32, 12_000.0, 70_000.0] {
        let 半径 = 大気内半径::生成する(&媒体, m(下端半径 + 高度)).unwrap();
        for mu in [1.0_f32, 0.3, 0.02] {
            let 余弦 = 天頂余弦::生成する(mu).unwrap();
            assert_eq!(
                上端までの透過率(&媒体, 半径, 余弦, 標本数()),
                上端までの透過率(&媒体, 半径, 余弦, 標本数())
            );
            let 分布 = 媒体.ミー().密度分布();
            assert_eq!(
                上端までの光学距離(&媒体, &分布, 半径, 余弦, 標本数()).値(),
                上端までの光学距離(&媒体, &分布, 半径, 余弦, 標本数()).値()
            );
        }
    }
}
