//! 太陽相対フレームの検査。正規直交と往復の恒等・写した向きから求めたスカイビューの視線がワールドのまま求めた視線と一致すること・太陽の方位を回しても写した向きが変わらないことを見る。
//! 後ろの2つが、遠方環境をこのフレームで焼くと鍵に太陽の方位が要らなくなる根拠である。

use crate::atmosphere::{
    ワールドの視線からスカイビューのベイク済み画像の視線を求める, 太陽相対フレーム, 太陽相対座標の太陽方向
};

fn 単位化した(向き: [f64; 3]) -> [f64; 3] {
    let 長さ = (向き[0] * 向き[0] + 向き[1] * 向き[1] + 向き[2] * 向き[2]).sqrt();
    [向き[0] / 長さ, 向き[1] / 長さ, 向き[2] / 長さ]
}

/// 天頂余弦と方位角から太陽の向きを組む。方位角は東(+X)から南(+Z)へ回る角である。
fn 太陽の向き(天頂余弦: f64, 方位角: f64) -> [f64; 3] {
    let 水平 = (1.0 - 天頂余弦 * 天頂余弦).max(0.0).sqrt();
    [水平 * 方位角.cos(), 天頂余弦, 水平 * 方位角.sin()]
}

fn 視線一覧() -> [[f64; 3]; 5] {
    [
        単位化した([0.3, 0.9, -0.2]),
        単位化した([-0.7, 0.1, 0.5]),
        単位化した([0.0, 1.0, 0.0]),
        単位化した([0.2, -0.6, 0.8]),
        単位化した([1.0, 0.0, 0.0]),
    ]
}

/// フレームの3軸は互いに直交し長さが1である。写して戻す往復は元の向きへ戻る。
#[test]
fn 正規直交であり往復が恒等である() {
    let フレーム = 太陽相対フレーム::太陽方向から組む(太陽の向き(0.5, 1.1));
    for 視線 in 視線一覧() {
        let 写した = フレーム.ワールドの向きを写す(視線);
        let 長さ二乗: f64 = 写した.iter().map(|値| 値 * 値).sum();
        assert!((長さ二乗 - 1.0).abs() < 1.0e-12, "写した向きの長さ二乗が{長さ二乗}になった");
        let 戻した = フレーム.ワールドの向きへ戻す(写した);
        for 添字 in 0..3 {
            assert!((戻した[添字] - 視線[添字]).abs() < 1.0e-12, "往復で{視線:?}が{戻した:?}になった");
        }
    }
}

/// 太陽相対座標へ写した視線と太陽相対の太陽から求めた視線は、ワールドのまま求めた視線と一致する。
#[test]
fn 太陽相対で求めた視線がワールドで求めた視線と一致する() {
    for 天頂余弦 in [-0.4_f64, 0.0, 0.3, 0.87] {
        for 方位角 in [0.0_f64, 1.3, 3.0, 5.5] {
            let 太陽 = 太陽の向き(天頂余弦, 方位角);
            let フレーム = 太陽相対フレーム::太陽方向から組む(太陽);
            let 太陽相対の太陽 = 太陽相対座標の太陽方向(天頂余弦);
            for 視線 in 視線一覧() {
                let ワールド = ワールドの視線からスカイビューのベイク済み画像の視線を求める(視線, 太陽).unwrap();
                let 相対 = ワールドの視線からスカイビューのベイク済み画像の視線を求める(
                    フレーム.ワールドの向きを写す(視線),
                    太陽相対の太陽,
                )
                .unwrap();
                let 天頂差 = f64::from(ワールド.視線天頂余弦.値() - 相対.視線天頂余弦.値());
                let 方位差 = f64::from(ワールド.太陽方位余弦.値() - 相対.太陽方位余弦.値());
                assert!(天頂差.abs() < 1.0e-6, "天頂余弦が{天頂差}ずれた");
                assert!(方位差.abs() < 1.0e-6, "方位余弦が{方位差}ずれた");
            }
        }
    }
}

/// 太陽の高度を保ったまま方位だけを回すと、同じワールドの向きを回した先の視線が写した向きの視線と一致する。
/// 太陽相対座標で焼いた内容が太陽の方位に依らないことを、この不変性が表す。
#[test]
fn 太陽の方位を回しても写した向きが同じである() {
    let 天頂余弦 = 0.45;
    let 基準 = 太陽相対フレーム::太陽方向から組む(太陽の向き(天頂余弦, 0.0));
    for 方位角 in [0.7_f64, 2.2, 4.9] {
        let 回した = 太陽相対フレーム::太陽方向から組む(太陽の向き(天頂余弦, 方位角));
        for 視線 in 視線一覧() {
            let 元 = 基準.ワールドの向きを写す(視線);
            // 同じ角だけ回した視線は、回したフレームで写すと元と同じ太陽相対座標になる。
            let 回した視線 = [
                視線[0] * 方位角.cos() - 視線[2] * 方位角.sin(),
                視線[1],
                視線[0] * 方位角.sin() + 視線[2] * 方位角.cos(),
            ];
            let 写した = 回した.ワールドの向きを写す(回した視線);
            for 添字 in 0..3 {
                assert!((写した[添字] - 元[添字]).abs() < 1.0e-12, "方位{方位角}で{元:?}が{写した:?}になった");
            }
        }
    }
}

/// 太陽が天頂にある(水平成分が失われる)ときも、フレームは正規直交のまま組める。
#[test]
fn 太陽が天頂でもフレームが組める() {
    let フレーム = 太陽相対フレーム::太陽方向から組む([0.0, 1.0, 0.0]);
    let 写した = フレーム.ワールドの向きを写す(単位化した([0.6, 0.5, -0.3]));
    let 長さ二乗: f64 = 写した.iter().map(|値| 値 * 値).sum();
    assert!((長さ二乗 - 1.0).abs() < 1.0e-12, "天頂の太陽で長さ二乗が{長さ二乗}になった");
}
