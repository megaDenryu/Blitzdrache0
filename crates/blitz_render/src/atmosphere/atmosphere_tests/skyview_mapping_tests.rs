//! スカイビューのベイク済み画像の写像の検査。往復が恒等であること・軸の両端が何を表すか・地平線が縦の中央に来ること・
//! 単位位置とテクセル中心のUVの往復を見る。焼いた値は`skyview_lut_tests`が別に見る。

use super::地球標準の媒体;
use crate::atmosphere::{
    スカイビューのベイク済み画像の単位位置を求める, スカイビューのベイク済み画像の視線, スカイビューのベイク済み画像の視線を求める,
    単位位置からテクセル中心のuv, 大気のベイク済み画像の解像度, 天頂余弦, 方位余弦, 端から端への単位位置,
};

/// 地表から少し浮かせた観測点。地表ちょうどでも写像は定義されるが、代表として目の高さを採る。
fn 観測半径() -> f64 {
    f64::from(super::下端半径) + 1.5
}

/// 単位位置の格子を往復させ、元の位置へ戻ることを確かめる。写像と逆写像が食い違えば、焼いた座標と参照する座標が
/// ずれて空の色が静かに変わるため、この往復が正本の側の唯一の防波堤である。
#[test]
fn 単位位置の往復が恒等である() {
    let 媒体 = 地球標準の媒体();
    let 半径 = 観測半径();
    for 横段 in 0..=8 {
        for 縦段 in 0..=8 {
            let 横位置 = f64::from(横段) / 8.0;
            let 縦位置 = f64::from(縦段) / 8.0;
            let 視線 = スカイビューのベイク済み画像の視線を求める(&媒体, 半径, 横位置, 縦位置).unwrap();
            let [戻り横, 戻り縦] = スカイビューのベイク済み画像の単位位置を求める(&媒体, 半径, 視線);
            assert!((戻り横 - 横位置).abs() < 1.0e-5, "横{横位置}が{戻り横}へ戻った");
            assert!((戻り縦 - 縦位置).abs() < 1.0e-5, "縦{縦位置}が{戻り縦}へ戻った");
        }
    }
}

/// 縦の0が天頂、0.5が地平線、1が天底を表す。地表付近では地平線の天頂余弦がほぼ0である。
#[test]
fn 縦軸の端と中央が天頂と地平線と天底を表す() {
    let 媒体 = 地球標準の媒体();
    let 半径 = 観測半径();
    let 天頂 = スカイビューのベイク済み画像の視線を求める(&媒体, 半径, 0.0, 0.0).unwrap();
    let 地平線 = スカイビューのベイク済み画像の視線を求める(&媒体, 半径, 0.0, 0.5).unwrap();
    let 天底 = スカイビューのベイク済み画像の視線を求める(&媒体, 半径, 0.0, 1.0).unwrap();
    assert!((天頂.視線天頂余弦.値() - 1.0).abs() < 1.0e-5, "天頂が{}", 天頂.視線天頂余弦.値());
    assert!(地平線.視線天頂余弦.値().abs() < 1.0e-3, "地平線が{}", 地平線.視線天頂余弦.値());
    assert!((天底.視線天頂余弦.値() + 1.0).abs() < 1.0e-5, "天底が{}", 天底.視線天頂余弦.値());
}

/// 横の0が太陽と同じ方位、1が反対の方位を表す。
#[test]
fn 横軸の端が太陽の方位と反対の方位を表す() {
    let 媒体 = 地球標準の媒体();
    let 半径 = 観測半径();
    let 太陽側 = スカイビューのベイク済み画像の視線を求める(&媒体, 半径, 0.0, 0.25).unwrap();
    let 反対側 = スカイビューのベイク済み画像の視線を求める(&媒体, 半径, 1.0, 0.25).unwrap();
    assert!((太陽側.太陽方位余弦.値() - 1.0).abs() < 1.0e-5, "太陽側が{}", 太陽側.太陽方位余弦.値());
    assert!((反対側.太陽方位余弦.値() + 1.0).abs() < 1.0e-5, "反対側が{}", 反対側.太陽方位余弦.値());
}

/// 観測点を上げると地平線が下がり、縦0.5に対応する天頂余弦が負へ動く。
#[test]
fn 観測点を上げると地平線が下がる() {
    let 媒体 = 地球標準の媒体();
    let 低い = スカイビューのベイク済み画像の視線を求める(&媒体, 観測半径(), 0.0, 0.5).unwrap();
    let 高い = スカイビューのベイク済み画像の視線を求める(&媒体, f64::from(super::下端半径) + 20_000.0, 0.0, 0.5).unwrap();
    assert!(高い.視線天頂余弦.値() < 低い.視線天頂余弦.値() - 0.01);
}

/// 地平線より下を向く視線は縦0.5以上へ、上を向く視線は0.5未満へ写る。
#[test]
fn 地平線の上下で縦の半分が分かれる() {
    let 媒体 = 地球標準の媒体();
    let 半径 = f64::from(super::下端半径) + 10_000.0;
    for (余弦, 上か) in [(0.9_f32, true), (0.01, true), (-0.01, true), (-0.2, false), (-0.9, false)] {
        let 視線 = スカイビューのベイク済み画像の視線 {
            視線天頂余弦: 天頂余弦::生成する(余弦).unwrap(),
            太陽方位余弦: 方位余弦::生成する(0.0).unwrap(),
        };
        let [_, 縦] = スカイビューのベイク済み画像の単位位置を求める(&媒体, 半径, 視線);
        assert_eq!(縦 < 0.5, 上か, "天頂余弦{余弦}の縦位置が{縦}");
    }
}

/// 添字から単位位置、単位位置からテクセル中心のUVへの往復が、元のテクセル中心へ戻る。
#[test]
fn 単位位置とテクセル中心のuvの往復が恒等である() {
    let 解像度 = 大気のベイク済み画像の解像度::既定値();
    for 辺 in [解像度.スカイビューの幅(), 解像度.スカイビューの高さ(), 解像度.多重散乱の一辺()] {
        for 添字 in [0, 1, 辺 / 2, 辺 - 2, 辺 - 1] {
            let 単位位置 = f64::from(端から端への単位位置(添字, 辺));
            let uv = 単位位置からテクセル中心のuv(単位位置, 辺);
            let 期待 = (f64::from(添字) + 0.5) / f64::from(辺);
            assert!((uv - 期待).abs() < 1.0e-6, "辺{辺}の添字{添字}で{uv}(期待{期待})");
        }
    }
}
