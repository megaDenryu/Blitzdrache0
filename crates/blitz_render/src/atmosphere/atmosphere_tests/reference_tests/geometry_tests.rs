//! 視線を持つ量のうち、閉じた式で決まる幾何の参照一致検査。球との交差距離と地平線の向きを見る。

use super::super::super::{地平線の天頂余弦, 大気上端までの距離, 惑星までの距離};
use super::super::reference_record::参照レコード;
use super::super::地球標準の媒体;
use super::{一致するか, 参照レコード一覧, 相対誤差, 視線};

#[test]
fn 交差距離と地平線が参照と一致する() {
    let 媒体 = 地球標準の媒体();
    let mut 件数 = [0_u32; 3];
    for レコード in 参照レコード一覧() {
        match レコード {
            参照レコード::地平線 {
                半径, 天頂余弦: 期待
            } => {
                件数[0] += 1;
                let (観測半径, _) = 視線(&媒体, 半径, 0.0);
                let 実測 = 地平線の天頂余弦(&媒体, 観測半径).値();
                assert!(一致するか(実測, 期待), "半径{半径}の地平線で誤差{}", 相対誤差(実測, 期待));
            }
            参照レコード::上端距離 {
                半径, 天頂余弦: 余弦, 距離
            } => {
                件数[1] += 1;
                let (観測半径, 向き) = 視線(&媒体, 半径, 余弦);
                let 実測 = 大気上端までの距離(&媒体, 観測半径, 向き).値();
                assert!(一致するか(実測, 距離), "半径{半径}の余弦{余弦}の上端距離で誤差{}", 相対誤差(実測, 距離));
            }
            参照レコード::地表距離 {
                半径, 天頂余弦: 余弦, 距離
            } => {
                件数[2] += 1;
                let (観測半径, 向き) = 視線(&媒体, 半径, 余弦);
                let 実測 = 惑星までの距離(&媒体, 観測半径, 向き)
                    .unwrap_or_else(|| panic!("半径{半径}の余弦{余弦}で参照は交差するのに交差しないと判定した"))
                    .値();
                assert!(一致するか(実測, 距離), "半径{半径}の余弦{余弦}の地表距離で誤差{}", 相対誤差(実測, 距離));
            }
            _ => {}
        }
    }
    assert_eq!(件数, [8, 64, 32], "交差のレコード件数が変わった");
}
