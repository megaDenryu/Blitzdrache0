//! 視線を持つ量のうち、経路に沿った数値積分で決まる量の参照一致検査。光学距離と透過率を見る。

use super::super::super::{上端までの光学距離, 上端までの透過率, 積分標本数};
use super::super::reference_record::参照レコード;
use super::super::地球標準の媒体;
use super::{一致するか, 参照の区間数, 参照レコード一覧, 相対誤差, 視線};

#[test]
fn 光学距離が参照と一致する() {
    let 媒体 = 地球標準の媒体();
    let 標本数 = 積分標本数::生成する(参照の区間数).unwrap();
    let 分布一覧 = [媒体.レイリー().密度分布(), 媒体.ミー().密度分布(), 媒体.吸収().密度分布()];
    let mut 件数 = 0;
    for レコード in 参照レコード一覧() {
        let 参照レコード::光学距離 {
            半径,
            天頂余弦: 余弦,
            レイリー,
            ミー,
            吸収,
        } = レコード
        else {
            continue;
        };
        件数 += 1;
        let (観測半径, 向き) = 視線(&媒体, 半径, 余弦);
        for (添字, 期待) in [レイリー, ミー, 吸収].into_iter().enumerate() {
            let 実測 = 上端までの光学距離(&媒体, &分布一覧[添字], 観測半径, 向き, 標本数).値();
            let 誤差 = 相対誤差(実測, 期待);
            assert!(
                一致するか(実測, 期待),
                "半径{半径}の余弦{余弦}の成分{添字}で誤差{誤差}、実測{実測}、参照{期待}"
            );
        }
    }
    assert_eq!(件数, 64, "光学距離のレコード件数が変わった");
}

#[test]
fn 透過率が参照と一致する() {
    let 媒体 = 地球標準の媒体();
    let 標本数 = 積分標本数::生成する(参照の区間数).unwrap();
    let mut 件数 = 0;
    for レコード in 参照レコード一覧() {
        let 参照レコード::透過率 {
            半径, 天頂余弦: 余弦, 成分
        } = レコード
        else {
            continue;
        };
        件数 += 1;
        let (観測半径, 向き) = 視線(&媒体, 半径, 余弦);
        let 実測 = 上端までの透過率(&媒体, 観測半径, 向き, 標本数).成分();
        for (添字, 期待) in 成分.into_iter().enumerate() {
            let 誤差 = 相対誤差(実測[添字], 期待);
            assert!(
                一致するか(実測[添字], 期待),
                "半径{半径}の余弦{余弦}のチャネル{添字}で誤差{誤差}、参照{期待}"
            );
        }
    }
    assert_eq!(件数, 64, "透過率のレコード件数が変わった");
}
