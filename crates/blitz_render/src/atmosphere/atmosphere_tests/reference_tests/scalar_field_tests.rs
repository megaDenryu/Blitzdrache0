//! 視線を持たない量の参照一致検査。高度だけで決まる密度と、散乱角だけで決まる位相関数を見る。

use super::super::super::{ミー位相関数, レイリー位相関数, 位相非対称係数, 散乱角余弦, 規格化密度を求める};
use super::super::reference_record::参照レコード;
use super::super::{m, 地球標準の媒体};
use super::{一致するか, 参照レコード一覧, 相対誤差};
use crate::atmosphere::narrowing::実数へ狭める;

#[test]
fn 密度が参照と一致する() {
    let 媒体 = 地球標準の媒体();
    let 分布一覧 = [媒体.レイリー().密度分布(), 媒体.ミー().密度分布(), 媒体.吸収().密度分布()];
    let mut 件数 = 0;
    for レコード in 参照レコード一覧() {
        let 参照レコード::密度 {
            高度, レイリー, ミー, 吸収
        } = レコード
        else {
            continue;
        };
        件数 += 1;
        let 高さ = m(実数へ狭める(高度));
        for (添字, 期待) in [レイリー, ミー, 吸収].into_iter().enumerate() {
            let 実測 = 規格化密度を求める(&分布一覧[添字], 高さ).値();
            let 誤差 = 相対誤差(実測, 期待);
            assert!(一致するか(実測, 期待), "高度{高度}の成分{添字}で誤差{誤差}、実測{実測}、参照{期待}");
        }
    }
    assert_eq!(件数, 16, "密度のレコード件数が変わった");
}

#[test]
fn 位相関数が参照と一致する() {
    let 係数 = 位相非対称係数::生成する(super::super::位相非対称係数).unwrap();
    let mut 件数 = 0;
    for レコード in 参照レコード一覧() {
        let 参照レコード::位相 {
            散乱角余弦: 余弦,
            レイリー,
            ミー,
        } = レコード
        else {
            continue;
        };
        件数 += 1;
        let 入力 = 散乱角余弦::生成する(実数へ狭める(余弦)).unwrap();
        let レイリー実測 = レイリー位相関数(入力).毎ステラジアン();
        assert!(
            一致するか(レイリー実測, レイリー),
            "散乱角余弦{余弦}のレイリーで誤差{}",
            相対誤差(レイリー実測, レイリー)
        );
        let ミー実測 = ミー位相関数(係数, 入力).毎ステラジアン();
        assert!(一致するか(ミー実測, ミー), "散乱角余弦{余弦}のミーで誤差{}", 相対誤差(ミー実測, ミー));
    }
    assert_eq!(件数, 10, "位相のレコード件数が変わった");
}
