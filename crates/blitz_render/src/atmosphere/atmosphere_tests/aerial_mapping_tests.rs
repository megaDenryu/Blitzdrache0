//! 空中遠近ボリュームの焼く側の写像と参照する側の写像が同じ格子を指すことの検査。
//! 参照する側は全画面合成パスがボリュームを標本する唯一の入口であり、焼く側とずれると霞の量が画面ぜんたいで
//! 静かにずれる。ずれは絵にしか現れないため、格子の一致をここが数で確かめる。
//! 写しは`shaders/atmosphere_aerial_mapping.slang`にある。

use crate::atmosphere::mapping::aerial_mapping::{
    空中遠近ボリュームの奥行き位置を求める, 空中遠近ボリュームの奥行き添字の位置, 空中遠近ボリュームの標本座標を求める,
    空中遠近ボリュームの画面位置を求める, 空中遠近ボリュームの距離を求める,
};

const 一辺: u32 = 32;
const 最遠距離: f64 = 500.0;

/// 焼いたボクセルの条件をそのまま参照すると、そのボクセルの中心のUVになる。
/// 中心を指すUVは線形補間が隣を1つも混ぜないため、この一致が「焼いた値をそのまま参照できる」ことを意味する。
#[test]
fn ボクセルの条件を参照するとそのボクセルの中心を指す() {
    for (横, 縦, 奥) in [(0, 0, 0), (5, 17, 1), (一辺 / 2, 一辺 / 2, 一辺 / 2), (一辺 - 1, 一辺 - 1, 一辺 - 1)] {
        let 画面位置 = 空中遠近ボリュームの画面位置を求める(横, 縦, 一辺);
        let 距離 = 空中遠近ボリュームの距離を求める(最遠距離, 空中遠近ボリュームの奥行き添字の位置(奥, 一辺));
        let 奥行き位置 = 空中遠近ボリュームの奥行き位置を求める(最遠距離, 距離);
        let 座標 = 空中遠近ボリュームの標本座標を求める(画面位置, 奥行き位置, 一辺);
        let 期待 = [中心のuv(横), 中心のuv(縦), 中心のuv(奥)];
        for 軸 in 0..3 {
            assert!(
                (座標[軸] - 期待[軸]).abs() < 1.0e-12,
                "軸{軸}のUVがボクセル({横},{縦},{奥})の中心と食い違う: {} と {}",
                座標[軸],
                期待[軸]
            );
        }
    }
}

/// 距離0は先頭スライスの中心を、最遠距離は末尾スライスの中心を指す。
/// 先頭が散乱0・透過率1の厳密な値を持つため、至近の面が霞まないことをこの端の一致が保つ。
#[test]
fn 両端の距離が両端のスライスの中心を指す() {
    let 画面位置 = [0.25, 0.75];
    let 至近 = 空中遠近ボリュームの標本座標を求める(画面位置, 空中遠近ボリュームの奥行き位置を求める(最遠距離, 0.0), 一辺);
    let 最遠 = 空中遠近ボリュームの標本座標を求める(画面位置, 空中遠近ボリュームの奥行き位置を求める(最遠距離, 最遠距離), 一辺);
    assert!((至近[2] - 中心のuv(0)).abs() < 1.0e-12, "{}", 至近[2]);
    assert!((最遠[2] - 中心のuv(一辺 - 1)).abs() < 1.0e-12, "{}", 最遠[2]);
}

/// 最遠距離より遠い距離は末尾スライスへ張り付き、それより遠くへは進まない。
#[test]
fn 最遠より遠い距離は末尾スライスへ張り付く() {
    let 位置 = 空中遠近ボリュームの奥行き位置を求める(最遠距離, 最遠距離 * 4.0);
    let 座標 = 空中遠近ボリュームの標本座標を求める([0.5, 0.5], 位置, 一辺);
    assert!((座標[2] - 中心のuv(一辺 - 1)).abs() < 1.0e-12, "{}", 座標[2]);
}

/// 横縦は画面の位置がそのままUVになる。参照する側が画素の画面位置を1つも直さずに渡せることを意味する。
#[test]
fn 横縦の標本座標は画面の位置そのままである() {
    let 画面位置 = [0.125, 0.875];
    let 座標 = 空中遠近ボリュームの標本座標を求める(画面位置, 0.5, 一辺);
    assert!((座標[0] - 画面位置[0]).abs() < 1.0e-12, "{}", 座標[0]);
    assert!((座標[1] - 画面位置[1]).abs() < 1.0e-12, "{}", 座標[1]);
}

fn 中心のuv(添字: u32) -> f64 {
    (f64::from(添字) + 0.5) / f64::from(一辺)
}
