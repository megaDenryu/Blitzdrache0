//! 写像の逆と、セルの中央へ落ちる入力を、クラスタ写像の実装を1度も呼ばずに書き下した式。受け取るのは
//! 画素と奥行き、またはセル添字。返すのはビュー空間の位置、または画素と奥行きの組である。
//!
//! 検査の期待値をここだけから作るために置く。写像や錐台の導出を呼んで期待値を組み立てると、検査が実装の
//! 言い直しになり、往路と復路を同じ向きに壊した誤りを1件も落とせなくなる。
//!
//! 使う入力は画面の寸法・分割数・奥行きの近と遠・視野の半角の正接という、写像の生成に渡した値だけである。

use blitz_math::{ビュー, メートル, 位置};

use crate::numeric::floor_index::実数位置の床の添字;

use super::cell_index::クラスタ格子のセル添字;
use super::narrowing::単精度へ狭める;
use super::test_fixture::{横の半角の正接, 画面の幅, 画面の高さ, 縦の半角の正接, 近い奥行き, 遠い奥行き};

/// 画素の中心とカメラからの奥行きが指すビュー空間の位置。正規化装置座標は横が右、縦が下を正とし、
/// ビュー空間は縦が上、視線が奥行きの負の向きである。
pub(super) fn 画素中心のビュー空間の位置(画素の横: u32, 画素の縦: u32, 奥行き: f32) -> 位置<ビュー> {
    let 正規化横 = 単精度へ狭める(2.0 * (f64::from(画素の横) + 0.5) / f64::from(画面の幅) - 1.0);
    let 正規化縦 = 単精度へ狭める(2.0 * (f64::from(画素の縦) + 0.5) / f64::from(画面の高さ) - 1.0);
    位置::生成する(
        メートル::生成する(正規化横 * 横の半角の正接 * 奥行き),
        メートル::生成する(-正規化縦 * 縦の半角の正接 * 奥行き),
        メートル::生成する(-奥行き),
    )
}

/// セルの中央へ落ちるはずの画素と奥行き。画面の寸法・分割数・奥行きの近と遠だけから組み立て、
/// クラスタ写像も錐台の導出も1度も呼ばない。全射性の検査がこれを期待入力に使う。
pub(super) fn セルの中央へ落ちる画素と奥行き(添字: クラスタ格子のセル添字) -> (u32, u32, メートル) {
    let 分割数 = 添字.分割数();
    let 段の中での位置 = (f64::from(添字.奥行き()) + 0.5) / f64::from(分割数.奥行き());
    let 近と遠の比 = f64::from(遠い奥行き) / f64::from(近い奥行き);
    let 奥行き = 単精度へ狭める(f64::from(近い奥行き) * 近と遠の比.powf(段の中での位置));
    (
        タイルの中央の画素(添字.横(), 分割数.横(), 画面の幅),
        タイルの中央の画素(添字.縦(), 分割数.縦(), 画面の高さ),
        メートル::生成する(奥行き),
    )
}

fn タイルの中央の画素(添字: u32, 分割数: u32, 画素数: u32) -> u32 {
    実数位置の床の添字((f64::from(添字) + 0.5) / f64::from(分割数) * f64::from(画素数), 画素数 - 1)
}
