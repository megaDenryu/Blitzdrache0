//! 読み戻したクラスタ格子がGPU側の書式に従っているかの検査。受け取るのは長さと区間、返すのは受理か型付きの失敗かである。
//!
//! 長さの食い違いを入口で失敗にするのは、読み戻しの長さが格子から決まる値であり、違っていれば読み戻しか
//! 格子の確保のどちらかが壊れているためである。足りないぶんを0で埋めると、その破れが「割り当てが少ない」という
//! 正常に見える統計へ化ける。
//!
//! 区間1つずつの書式も同じ理由で確かめる。選別はセルごとに同じ長さの区間を割り当てるため、開始位置は
//! 一次元の添字とセル1つの上限件数だけで決まり、件数はその上限を超えない。この2つが破れたまま数を数えると、
//! 別のセルの添字列を読んで作った統計が正常な値として出る。

use super::cell_light_capacity::セル1つが指せる局所光の上限件数;
use super::cell_light_interval::{セルの光の区間, 区間の書式の検査結果};
use super::input_error::クラスタ多光源入力エラー;

/// 区間1つがGPU側の書式に従っているかを確かめる。従わない区間はそこで型付きの失敗にする。
pub(super) fn 区間の書式を確かめる(
    区間: セルの光の区間, 一次元の添字: u32
) -> Result<(), クラスタ多光源入力エラー> {
    let 上限 = 件数へ写す(セル1つが指せる局所光の上限件数);
    match 区間.取り方に従うか(一次元の添字, 上限) {
        区間の書式の検査結果::取り方どおり => Ok(()),
        区間の書式の検査結果::開始位置が取り方と違う { 期待値 } => {
            Err(クラスタ多光源入力エラー::読み戻した区間の開始位置が取り方と違う {
                一次元の添字,
                開始位置: 区間.開始位置(),
                期待値,
            })
        }
        区間の書式の検査結果::件数が上限を超えた => {
            Err(クラスタ多光源入力エラー::読み戻した区間の件数が上限を超えた {
                一次元の添字,
                件数: 区間.件数(),
                上限,
            })
        }
    }
}

pub(super) fn 長さを確かめる(
    区間の件数: usize,
    セルの総数: usize,
    添字列の要素数: usize,
    期待する要素数: usize,
) -> Result<(), クラスタ多光源入力エラー> {
    if 区間の件数 != セルの総数 {
        return Err(クラスタ多光源入力エラー::読み戻した区間表の件数が格子と違う {
            件数: 件数へ写す(区間の件数),
            期待値: 件数へ写す(セルの総数),
        });
    }
    if 添字列の要素数 != 期待する要素数 {
        return Err(クラスタ多光源入力エラー::読み戻した光添字列の要素数が格子と違う {
            要素数: 件数へ写す(添字列の要素数),
            期待値: 件数へ写す(期待する要素数),
        });
    }
    Ok(())
}

fn 件数へ写す(値: usize) -> u32 {
    u32::try_from(値).unwrap_or_else(|_| panic!("数えた件数が符号なし32ビットに収まらないという不変条件の破れ: {値}"))
}

#[cfg(test)]
mod tests {
    use super::super::cell_light_capacity::セル1つが指せる局所光の上限件数;
    use super::super::cell_light_interval::セルの光の区間;
    use super::{区間の書式を確かめる, 長さを確かめる};

    fn 上限() -> u32 {
        u32::try_from(セル1つが指せる局所光の上限件数).unwrap_or(0)
    }

    #[test]
    fn 取り方どおりの区間を受ける() {
        assert!(区間の書式を確かめる(セルの光の区間::生成する(0, 0), 0).is_ok());
        assert!(区間の書式を確かめる(セルの光の区間::生成する(上限() * 7, 上限()), 7).is_ok());
    }

    /// 開始位置が別のセルを指していると、そのセルの添字列でなく隣のセルの添字列を読んだ統計が正常な値として出る。
    #[test]
    fn 開始位置が取り方と違う区間を失敗にする() {
        assert!(区間の書式を確かめる(セルの光の区間::生成する(上限() * 7 + 1, 1), 7).is_err());
        assert!(区間の書式を確かめる(セルの光の区間::生成する(0, 1), 7).is_err());
    }

    #[test]
    fn 件数が上限を超えた区間を失敗にする() {
        assert!(区間の書式を確かめる(セルの光の区間::生成する(0, 上限() + 1), 0).is_err());
    }

    #[test]
    fn 長さが合わない読み戻しを失敗にする() {
        assert!(長さを確かめる(3072, 3072, 196_608, 196_608).is_ok());
        assert!(長さを確かめる(3071, 3072, 196_608, 196_608).is_err());
        assert!(長さを確かめる(3072, 3072, 196_607, 196_608).is_err());
    }
}
