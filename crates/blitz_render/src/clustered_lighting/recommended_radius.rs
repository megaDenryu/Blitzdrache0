//! 強度と打ち切りの閾値から推奨の影響半径を導く工程。受け取るのは光の強度と打ち切りの閾値、返すのは
//! 推奨の影響半径である。
//!
//! 窓を掛ける前の逆二乗が閾値まで落ちる距離を返すのは、窓を掛けた式が半径そのものを未知数に含み、
//! 解が半径の定義に依存する循環になるためである。窓は半径で0へ落ちるため、この距離を半径に採ると
//! 実際の放射は閾値より手前で閾値を下回る。つまり返す値は届く範囲の上からの見積もりである。
//!
//! 世界を作る側が目安を得るための補助であり、既定値として黙って適用する経路は作らない。
//! 明るさの調整が届く範囲を黙って変える連動を作らないためである。
//! 参照: `_doc/設計/クラスタ多光源と点光源の影.md`

use blitz_math::メートル;

use crate::lighting_input::光強度;

use super::cutoff_threshold::打ち切りの閾値;
use super::influence_radius::影響半径;
use super::input_error::クラスタ多光源入力エラー;
use super::point_light_radiance::距離の二乗へ足す微小量;

/// 強度が閾値に対して小さすぎて正の半径が立たないときは、影響半径の生成が拒む。
pub fn 強度と打ち切りの閾値から推奨の影響半径を求める(
    強度: 光強度,
    閾値: 打ち切りの閾値,
) -> Result<影響半径, クラスタ多光源入力エラー> {
    let 半径の二乗 = 強度.値() / 閾値.値() - 距離の二乗へ足す微小量;
    影響半径::生成する(メートル::生成する(半径の二乗.sqrt()))
}
