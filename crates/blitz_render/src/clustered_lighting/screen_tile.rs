//! 画面のタイルの境界の往復。受け取るのは画素の位置または添字と、画素数と分割数。返すのはタイルの添字、
//! またはそのタイルが占める正規化装置座標の区間である。
//!
//! 往復の2方向を1つのファイルへ置くのは、どちらも同じ1つの規約(タイルの境界は正規化装置座標を分割数で
//! 等分した位置にあり、画素は中心で所属を決める)を使うためである。片方だけを直すと、光を割り当てたセルと
//! 画素が読むセルがタイルの縁で食い違い、縁に光の抜けが出る。
//!
//! 画素の中心で所属を決めるのは、画素段が受け取る画面の座標が画素の中心だからである。左上の角で決めると、
//! 分割数が画素数を割り切らないときにCPUの割り当てとGPUの参照が1タイルずれる。

use super::interval::区間;
use super::narrowing::単精度へ狭める;

/// 画素が属するタイルの添字。画素数の外へ出た画素は端のタイルへ入れ、どの入力にも1つの添字を返す。
/// 前提: 画素数と分割数はともに1以上である(クラスタ写像の生成が確かめる)。
pub(super) fn 画素からタイルの添字を求める(画素: u32, 画素数: u32, 分割数: u32) -> u32 {
    let 上限 = 分割数 - 1;
    let 画素の中心の二倍 = 2 * u64::from(画素) + 1;
    let 添字 = (画素の中心の二倍 * u64::from(分割数) / (2 * u64::from(画素数))).min(u64::from(上限));
    // 直前の`min`で上限以下へ落ちているため、この狭めは必ず成功する。代替値も同じ上限であり値は変わらない。
    u32::try_from(添字).unwrap_or(上限)
}

/// タイルが占める正規化装置座標の区間。左端が-1、右端が+1である。
/// 前提: 添字は分割数より小さい(セル添字の生成が確かめる)。
pub(super) fn タイルの添字から正規化装置座標の区間を求める(添字: u32, 分割数: u32) -> 区間<f32> {
    let タイルの幅 = 2.0 / f64::from(分割数);
    let 下限 = f64::from(添字) * タイルの幅 - 1.0;
    区間::生成する(単精度へ狭める(下限), 単精度へ狭める(下限 + タイルの幅))
}
