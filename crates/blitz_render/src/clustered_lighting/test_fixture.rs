//! 検査が共通で使う値の組み立て。受け取るのは画素・セル添字・中心と半径、返すのはクラスタ写像・
//! ビュー空間の位置・局所光の影響範囲の球である。固定した画面の寸法と視野をこの1箇所が持つ。
//!
//! 位置の組み立てを検査の側で持つのは、これが写像の逆を独立に書き下した式であり、写像の実装を呼び戻して
//! いないことを1箇所で見えるようにするためである。写像の内部を使って期待値を作ると、検査が実装の言い直しになる。
//!
//! 画面の寸法を分割数で割り切れない値にしてあるのは、タイルの境界が画素の途中へ落ちる場合を検査が必ず
//! 踏むためである。割り切れる寸法だけで確かめると、画素の中心と左上の角のどちらで所属を決めても答えが一致する。

use std::fmt::Debug;

use blitz_math::{ビュー, メートル, 位置};

use crate::extent::ウィンドウ寸法;
use crate::numeric::floor_index::実数位置の床の添字;

use super::cell_index::クラスタ格子のセル添字;
use super::cell_mapping::クラスタ写像;
use super::depth_range::クラスタの奥行き範囲;
use super::grid_division::クラスタ格子の分割数;
use super::half_field_of_view_tangent::視野の半角の正接;
use super::influence_radius::影響半径;
use super::light_sphere::局所光の影響範囲の球;
use super::narrowing::単精度へ狭める;

pub(super) const 画面の幅: u32 = 1913;
pub(super) const 画面の高さ: u32 = 1073;
pub(super) const 近い奥行き: f32 = 0.1;
pub(super) const 遠い奥行き: f32 = 200.0;
pub(super) const 横の半角の正接: f32 = 0.75;
pub(super) const 縦の半角の正接: f32 = 0.4;

/// 検査用の固定値から作る値は必ず成立するため、失敗は検査自身のバグである。
fn 検査用の固定値から作った値を取り出す<値, 誤り: Debug>(結果: Result<値, 誤り>) -> 値 {
    match 結果 {
        Ok(値) => 値,
        Err(理由) => panic!("検査用の固定値が値オブジェクトの不変条件を満たしていない: {理由:?}"),
    }
}

pub(super) fn 検査用のクラスタ写像() -> クラスタ写像 {
    let 奥行き範囲 = クラスタの奥行き範囲::生成する(メートル::生成する(近い奥行き), メートル::生成する(遠い奥行き));
    検査用の固定値から作った値を取り出す(クラスタ写像::生成する(
        クラスタ格子の分割数::仮置きの分割数を返す(),
        ウィンドウ寸法::生成する(画面の幅, 画面の高さ),
        検査用の固定値から作った値を取り出す(奥行き範囲),
        検査用の固定値から作った値を取り出す(視野の半角の正接::生成する(横の半角の正接, 縦の半角の正接)),
    ))
}

pub(super) fn 検査用の球を作る(中心: 位置<ビュー>, 半径: f32) -> 局所光の影響範囲の球 {
    let 影響半径 = 検査用の固定値から作った値を取り出す(影響半径::生成する(メートル::生成する(半径)));
    検査用の固定値から作った値を取り出す(局所光の影響範囲の球::生成する(中心, 影響半径))
}

pub(super) fn 検査用のセル添字を作る(横: u32, 縦: u32, 奥行き: u32) -> クラスタ格子のセル添字 {
    let 分割数 = 検査用のクラスタ写像().分割数();
    検査用の固定値から作った値を取り出す(クラスタ格子のセル添字::生成する(横, 縦, 奥行き, 分割数))
}

/// 画素の中心とカメラからの奥行きが指すビュー空間の位置。正規化装置座標は横が右、縦が下を正とし、
/// ビュー空間は縦が上、視線が奥行きの負の向きである。
pub(super) fn 画素中心のビュー空間の位置(画素の横: u32, 画素の縦: u32, 奥行き: f32) -> 位置<ビュー> {
    let 正規化横 = 単精度へ狭める(2.0 * (f64::from(画素の横) + 0.5) / f64::from(画面の幅) - 1.0);
    let 正規化縦 = 単精度へ狭める(2.0 * (f64::from(画素の縦) + 0.5) / f64::from(画面の高さ) - 1.0);
    位置::生成する(
        メートル::生成する(正規化横 * 横の半角の正接 * 奥行き),
        メートル::生成する(-正規化縦 * 縦の半角の正接 * 奥行き),
        メートル::生成する(-奥行き),
    )
}

/// セルの中央にあたるビュー空間の位置。奥行きは段の刻みが指数であるため相乗平均を採る。
pub(super) fn セル中央のビュー空間の位置(写像: クラスタ写像, 添字: クラスタ格子のセル添字) -> 位置<ビュー> {
    let 錐台 = 写像.セルの錐台を求める(添字);
    let 奥行き = (錐台.奥行きの区間().下限().値() * 錐台.奥行きの区間().上限().値()).sqrt();
    let 横の傾き = (錐台.横の傾きの区間().下限() + 錐台.横の傾きの区間().上限()) * 0.5;
    let 縦の傾き = (錐台.縦の傾きの区間().下限() + 錐台.縦の傾きの区間().上限()) * 0.5;
    位置::生成する(
        メートル::生成する(横の傾き * 奥行き),
        メートル::生成する(縦の傾き * 奥行き),
        メートル::生成する(-奥行き),
    )
}

/// ビュー空間の位置が落ちる画素。画素の中心の位置を組み立てる式の逆であり、床を取るだけである。
pub(super) fn ビュー空間の位置が落ちる画素(場所: 位置<ビュー>) -> (u32, u32) {
    let 奥行き = -場所.z().値();
    let 正規化横 = 場所.x().値() / (横の半角の正接 * 奥行き);
    let 正規化縦 = -場所.y().値() / (縦の半角の正接 * 奥行き);
    (画素の位置へ落とす(正規化横, 画面の幅), 画素の位置へ落とす(正規化縦, 画面の高さ))
}

fn 画素の位置へ落とす(正規化座標: f32, 画素数: u32) -> u32 {
    実数位置の床の添字((f64::from(正規化座標) + 1.0) * 0.5 * f64::from(画素数), 画素数 - 1)
}
