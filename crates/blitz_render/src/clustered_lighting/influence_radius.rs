//! 影響半径という量そのもの。触れる状態を持たず、担うのは有限かつ正であることの保証と、
//! 距離を半径で割った無次元の比を配ることである。
//!
//! 強度から導く値にしないのは、光が届く範囲が光を置く側の設計値だからである。導出値にすると明るさを
//! 調整しただけで届く範囲が黙って変わり、クラスタ格子のセルへの割り当てまで一緒に動く。
//! 参照: `_doc/設計/クラスタ多光源と点光源の影.md`

use blitz_math::メートル;

use super::input_error::クラスタ多光源入力エラー;

/// 1件の点光源が光を届かせる範囲の上限。この距離で減衰の窓が0になり、放射がちょうど0へ落ちる。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 影響半径(メートル);

impl 影響半径 {
    pub fn 生成する(長さ: メートル) -> Result<Self, クラスタ多光源入力エラー> {
        if !長さ.値().is_finite() || 長さ.値() <= 0.0 {
            return Err(クラスタ多光源入力エラー::影響半径不正(長さ.値()));
        }
        Ok(Self(長さ))
    }

    pub fn 長さ(self) -> メートル {
        self.0
    }

    /// 光からの距離が半径の何倍にあたるかを表す無次元の比。1でちょうど半径の上、1より大きいと外側である。
    /// 前提: 呼び出し元は距離として0以上の長さを与える(位置の差の長さがこれを満たす)。
    pub fn 半径に対する距離の比を求める(self, 距離: メートル) -> f32 {
        距離.値() / self.0.値()
    }
}
