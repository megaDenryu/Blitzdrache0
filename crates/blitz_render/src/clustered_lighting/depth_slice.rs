//! 奥行きの段の境界の往復。受け取るのは奥行きまたは段の添字と、奥行き範囲と分割数。返すのは段の添字、
//! またはその段が占める奥行きの区間である。
//!
//! 往復の2方向を1つのファイルへ置くのは、どちらも同じ1つの規約(段の境界は近と遠の比を分割数で等分した
//! 指数の刻みにある)を使うためである。片方だけを直すと、光を割り当てた段と画素段が読む段が食い違う。
//!
//! 刻みを指数にするのは、透視投影では手前ほど1段が覆う画面上の広さが小さく、等間隔の刻みだと手前の段へ
//! 光が集中するためである。

use blitz_math::メートル;

use crate::numeric::floor_index::実数位置の床の添字;

use super::depth_range::クラスタの奥行き範囲;
use super::interval::区間;
use super::narrowing::単精度へ狭める;

/// 奥行きが属する段の添字。近より手前は段0、遠より奥は最後の段へ入れ、どの入力にも1つの添字を返す。
/// 非数と0以下の奥行きは対数が非数か負の無限大になり、床の添字が段0へ落とす。
/// 前提: 分割数は1以上である(クラスタ格子の分割数の生成が確かめる)。
pub(super) fn 奥行きから段の添字を求める(奥行き: メートル, 範囲: クラスタの奥行き範囲, 分割数: u32) -> u32 {
    let 近 = f64::from(範囲.近().値());
    let 遠 = f64::from(範囲.遠().値());
    let 近に対する比 = f64::from(奥行き.値()) / 近;
    let 実数の段 = 近に対する比.ln() / (遠 / 近).ln() * f64::from(分割数);
    実数位置の床の添字(実数の段, 分割数 - 1)
}

/// 段が占める奥行きの区間。手前側と奥側の2つを返す。
/// 前提: 添字は分割数より小さい(セル添字の生成が確かめる)。
pub(super) fn 段の添字から奥行きの区間を求める(
    添字: u32, 範囲: クラスタの奥行き範囲, 分割数: u32
) -> 区間<メートル> {
    区間::生成する(
        段の境界の奥行き(f64::from(添字), 範囲, 分割数),
        段の境界の奥行き(f64::from(添字) + 1.0, 範囲, 分割数),
    )
}

fn 段の境界の奥行き(境界の番号: f64, 範囲: クラスタの奥行き範囲, 分割数: u32) -> メートル {
    let 近 = f64::from(範囲.近().値());
    let 遠 = f64::from(範囲.遠().値());
    メートル::生成する(単精度へ狭める(近 * (遠 / 近).powf(境界の番号 / f64::from(分割数))))
}
