//! 交差判定を1度も呼ばずに「本当に交わるか」を測る素朴な手段一式。受け取るのは錐台または点と向き、
//! 返すのは錐台の内側の標本の一覧・点どうしの距離・長さ1へそろえた向き・向きへ離した位置である。
//!
//! 4つを1つのファイルへ置くのは、どれも交差判定の期待値を独立に作るためだけに在り、他の用途を持たないためである。
//! 判定の答えを判定自身で確かめると検査が実装の言い直しになるため、この素朴な手を期待値の唯一の出どころにする。

use blitz_math::{ビュー, メートル, 位置};

use super::cell_frustum::クラスタ格子のセルの錐台;
use super::narrowing::単精度へ狭める;

const 軸ごとの刻み数: u32 = 8;

/// 錐台の奥行きと横と縦をそれぞれ等分した格子点。両端を含むため、角と辺の上の点も並ぶ。
pub(super) fn 錐台の内側の標本を並べる(錐台: クラスタ格子のセルの錐台) -> Vec<位置<ビュー>> {
    let mut 一覧 = Vec::new();
    for 奥の刻み in 0..=軸ごとの刻み数 {
        let 奥行き = 内分する(錐台.奥行きの区間().下限().値(), 錐台.奥行きの区間().上限().値(), 奥の刻み);
        for 横の刻み in 0..=軸ごとの刻み数 {
            let 横 = 内分する(錐台.横の傾きの区間().下限(), 錐台.横の傾きの区間().上限(), 横の刻み) * 奥行き;
            for 縦の刻み in 0..=軸ごとの刻み数 {
                let 縦 = 内分する(錐台.縦の傾きの区間().下限(), 錐台.縦の傾きの区間().上限(), 縦の刻み) * 奥行き;
                一覧.push(位置::生成する(
                    メートル::生成する(横),
                    メートル::生成する(縦),
                    メートル::生成する(-奥行き),
                ));
            }
        }
    }
    一覧
}

/// 錐台の標本のうち中心へ最も近いものまでの距離。標本が有限個であるため、真の最短距離の上からの見積もりである。
pub(super) fn 錐台の標本から中心までの最短の距離(錐台: クラスタ格子のセルの錐台, 中心: 位置<ビュー>) -> f32 {
    錐台の内側の標本を並べる(錐台)
        .into_iter()
        .map(|標本| 点と点の距離(標本, 中心))
        .fold(f32::INFINITY, f32::min)
}

pub(super) fn 点と点の距離(片方: 位置<ビュー>, もう片方: 位置<ビュー>) -> f32 {
    let 横 = 片方.x().値() - もう片方.x().値();
    let 縦 = 片方.y().値() - もう片方.y().値();
    let 奥 = 片方.z().値() - もう片方.z().値();
    (横 * 横 + 縦 * 縦 + 奥 * 奥).sqrt()
}

pub(super) fn 向きを長さ1へそろえる(成分: [f32; 3]) -> [f32; 3] {
    let 長さ = (成分[0] * 成分[0] + 成分[1] * 成分[1] + 成分[2] * 成分[2]).sqrt();
    [成分[0] / 長さ, 成分[1] / 長さ, 成分[2] / 長さ]
}

/// 基点から向きの側へ与えた距離だけ離れた位置。
pub(super) fn 向きへ離した位置(基点: 位置<ビュー>, 向き: [f32; 3], 距離: f32) -> 位置<ビュー> {
    位置::生成する(
        基点.x() + メートル::生成する(向き[0] * 距離),
        基点.y() + メートル::生成する(向き[1] * 距離),
        基点.z() + メートル::生成する(向き[2] * 距離),
    )
}

fn 内分する(下限: f32, 上限: f32, 刻み: u32) -> f32 {
    下限 + (上限 - 下限) * 単精度へ狭める(f64::from(刻み) / f64::from(軸ごとの刻み数))
}
