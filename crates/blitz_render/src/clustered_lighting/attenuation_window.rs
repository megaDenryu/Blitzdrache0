//! 減衰の窓という量そのもの。触れる状態を持たず、担うのは`clamp(1 - (距離 / 影響半径)の4乗, 0, 1)の2乗`という
//! 1つの式の保持と、値が0以上1以下に収まることの保証である。
//!
//! 逆二乗の放射へこの窓を掛けるのは、クラスタの打ち切りと絵を一致させるためである。逆二乗のままでは
//! 影響半径の外側でも寄与が0にならず、セルへ割り当てられた光と割り当てられなかった光の境目に段差が出る。
//! 指数を4に固定するのは、これを変えたくなったときが局所光レコードの版を上げるときだからである。
//! 参照: `_doc/設計/クラスタ多光源と点光源の影.md`

use blitz_math::メートル;

use super::influence_radius::影響半径;

/// 点光源の逆二乗の放射へ掛ける0以上1以下の係数。影響半径でちょうど0になる。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 減衰の窓(f32);

impl 減衰の窓 {
    /// 光からの距離と影響半径から窓を求める。距離が半径に等しいとき比の4乗が1になり、値は正確に0になる。
    /// 前提: 呼び出し元は距離として有限で0以上の長さを与える。有限でない距離は非数のまま伝わる。
    pub fn 距離と影響半径から求める(距離: メートル, 影響半径: 影響半径) -> Self {
        let 比 = 影響半径.半径に対する距離の比を求める(距離);
        let 比の二乗 = 比 * 比;
        let 比の四乗 = 比の二乗 * 比の二乗;
        let 内側 = (1.0 - 比の四乗).clamp(0.0, 1.0);
        Self(内側 * 内側)
    }

    pub fn 係数(self) -> f32 {
        self.0
    }
}
