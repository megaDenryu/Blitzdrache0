//! セル1つが指せる局所光の件数の上限と、クラスタ光添字列が持つ要素数。触れる状態を持たず、担うのは
//! 「セルごとに同じ長さの区間を割り当てる」という取り方の保持と、その取り方から要素数を導くことである。
//!
//! セルごとに同じ長さの区間を割り当てるのは、選別の答えを実行のたびに同じ並びにするためである。1本の列の
//! 先頭から詰める取り方だと開始位置がセルの処理順で変わり、同じセルの中の光の並びも変わる。並びが変われば
//! 足し合わせの順が変わり、同じ場面の同じ画素が実行ごとに最下位のビットで揺れる。
//!
//! 上限を局所光源列の上限件数と同じにするのは、1つのセルへ世界の光が全部届く場面(狭い部屋に光を並べた場面)で
//! 打ち切りが起きないようにするためである。打ち切りが起きないため、選別にも画素段にも「入り切らなかった光」の
//! 枝が要らない。
//! 参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断e: 光のセルへの割り当てはコンピュートで毎フレーム行い、書き込みは生成側のセットへ置く」

use crate::lighting_input::局所光源列;

use super::grid_division::クラスタ格子の分割数;

/// セル1つが指せる局所光の件数の上限。世界が宣言できる件数と同じであり、どのセルも全ての光を指せる。
pub const セル1つが指せる局所光の上限件数: usize = 局所光源列::上限件数;

/// その分割数の格子が要するクラスタ光添字列の要素数。セルの総数へ上限件数を掛けた値である。
///
/// 前提: 分割数の生成がセルの総数の収まりを確かめており、掛け算の相手は64である。
pub fn クラスタ光添字列の要素数(分割数: クラスタ格子の分割数) -> usize {
    let セルの総数 = usize::try_from(分割数.セルの総数()).unwrap_or_else(|_| panic!("セルの総数がusizeに収まらない"));
    セルの総数
        .checked_mul(セル1つが指せる局所光の上限件数)
        .unwrap_or_else(|| panic!("クラスタ光添字列の要素数がusizeに収まらない"))
}
