//! セル添字への写像とセルの錐台の整合の反証の検査。画素と奥行きから作った位置が、その入力が落ちたセルの
//! 錐台の内側にあることを見る。往路と復路のどちらかだけを書き換えた誤りをこれが落とす。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::cell_index::クラスタ格子のセル添字;
use super::independent_construction::画素中心のビュー空間の位置;
use super::test_fixture::{
    セル中央のビュー空間の位置, 検査用のクラスタ写像, 検査用のセルの錐台, 検査用のセル添字を作る, 検査用の一次元の添字から戻したセル添字, 画面の幅,
    画面の高さ, 近い奥行き, 遠い奥行き,
};

/// 画素の中心の位置が、その画素と奥行きが落ちたセルの錐台の内側にあるかを確かめる。
fn 画素の中心が自分のセルの錐台に含まれるか(画素の横: u32, 画素の縦: u32, 奥行き: f32) -> bool {
    let 写像 = 検査用のクラスタ写像();
    let 見る位置 = 画素中心のビュー空間の位置(画素の横, 画素の縦, 奥行き);
    let 添字 = 写像.画面の画素とビュー空間の奥行きからセル添字を求める(画素の横, 画素の縦, メートル::生成する(奥行き));
    検査用のセルの錐台(写像, 添字).位置を含むか(見る位置)
}

/// 画面の端と奥行きの端でも、画素の中心は自分のセルの錐台の内側にある。
#[test]
fn 画面と奥行きの端でも写像が返したセルの錐台は入力の位置を含む() {
    for 画素の横 in [0, 1, 599, 960, 画面の幅 - 1] {
        for 画素の縦 in [0, 1, 539, 画面の高さ - 1] {
            for 奥行き in [近い奥行き, 0.3, 1.0, 7.5, 60.0, 199.0, 遠い奥行き] {
                assert!(
                    画素の中心が自分のセルの錐台に含まれるか(画素の横, 画素の縦, 奥行き),
                    "画素({画素の横},{画素の縦})奥行き{奥行き}の位置が自分のセルの錐台の外にある"
                );
            }
        }
    }
}

/// 1行と1列を全画素なめる。タイルの境界が画素の途中に落ちる画素は分割数が画素数を割り切らないときにだけ現れ、
/// 数点の抜き取りでは踏めない。画素の中心でなく左上の角で所属を決める誤りをこれが落とす。
#[test]
fn 横の1行と縦の1列の全画素で写像が返したセルの錐台は入力の位置を含む() {
    for 画素の横 in 0..画面の幅 {
        assert!(
            画素の中心が自分のセルの錐台に含まれるか(画素の横, 537, 7.5),
            "横{画素の横}の画素が自分のセルの錐台の外にある"
        );
    }
    for 画素の縦 in 0..画面の高さ {
        assert!(
            画素の中心が自分のセルの錐台に含まれるか(951, 画素の縦, 7.5),
            "縦{画素の縦}の画素が自分のセルの錐台の外にある"
        );
    }
}

/// セルの中央はそのセルの錐台の内側にあり、隣のセルの錐台の外にある。
#[test]
fn セルの中央は自分の錐台にだけ含まれる() {
    let 写像 = 検査用のクラスタ写像();
    let 分割数 = 写像.分割数();
    for 一次元 in 0..分割数.セルの総数() {
        let 添字 = 検査用の一次元の添字から戻したセル添字(一次元);
        let 中央 = セル中央のビュー空間の位置(写像, 添字);
        assert!(検査用のセルの錐台(写像, 添字).位置を含むか(中央), "セル{一次元}が自分の中央を含まない");
        if let Ok(隣) = クラスタ格子のセル添字::一次元の添字から戻す(一次元 + 1, 分割数) {
            assert!(!検査用のセルの錐台(写像, 隣).位置を含むか(中央), "セル{一次元}の中央を隣のセルが含んだ");
        }
    }
}

/// 錐台どうしは奥行きの区間で隙間なく隣り合い、手前の段の遠い端が次の段の近い端に一致する。
#[test]
fn 奥行きの段は隙間なく隣り合う() {
    let 写像 = 検査用のクラスタ写像();
    let 分割数 = 写像.分割数();
    for 段 in 0..分割数.奥行き() - 1 {
        let 手前 = 検査用のセルの錐台(写像, 検査用のセル添字を作る(0, 0, 段));
        let 奥 = 検査用のセルの錐台(写像, 検査用のセル添字を作る(0, 0, 段 + 1));
        assert_eq!(
            手前.奥行きの区間().上限().値(),
            奥.奥行きの区間().下限().値(),
            "段{段}と次の段の境界が食い違う"
        );
        assert!(手前.奥行きの区間().下限().値() < 手前.奥行きの区間().上限().値());
    }
}

/// 段の刻みが指数であるなら、隣り合う段の奥行きの比はどの段でも等しい。等間隔の刻みへ戻した誤りをこれが落とす。
#[test]
fn 奥行きの段は指数の刻みで並ぶ() {
    let 写像 = 検査用のクラスタ写像();
    let 分割数 = 写像.分割数();
    let 期待の比 = (f64::from(遠い奥行き) / f64::from(近い奥行き)).powf(1.0 / f64::from(分割数.奥行き()));
    for 段 in 0..分割数.奥行き() {
        let 錐台 = 検査用のセルの錐台(写像, 検査用のセル添字を作る(0, 0, 段));
        let 比 = f64::from(錐台.奥行きの区間().上限().値()) / f64::from(錐台.奥行きの区間().下限().値());
        assert!((比 - 期待の比).abs() < 1.0e-5, "段{段}の刻みの比が他の段と違う: {比}");
    }
}
