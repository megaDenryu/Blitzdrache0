//! 減衰の窓の反証の検査。期待値は減衰の窓の式を通さず、手で解いた数と単調性の性質から
//! 独立に作る。実装を呼び戻して期待値を作ると、式を書き換えた誤りが検査を素通りする。
//! 点光源の放射そのものの反証は`point_light_radiance_tests.rs`が持つ。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::attenuation_window::減衰の窓;
use super::influence_radius::影響半径;
use super::narrowing::単精度へ狭める;

fn 半径10メートル() -> 影響半径 {
    影響半径::生成する(メートル::生成する(10.0)).unwrap()
}

fn 窓の係数(距離: f32) -> f32 {
    減衰の窓::距離と影響半径から求める(メートル::生成する(距離), 半径10メートル()).係数()
}

/// 影響半径でちょうど0にならなければ、セルへ割り当てられた光と割り当てられなかった光の境目に段差が出る。
#[test]
fn 窓は影響半径でちょうど0になり外側でも0のままである() {
    assert_eq!(窓の係数(10.0), 0.0);
    assert_eq!(窓の係数(10.5), 0.0);
    assert_eq!(窓の係数(1.0e6), 0.0);
    assert!(窓の係数(9.999) > 0.0);
}

#[test]
fn 窓は距離0で1であり0以上1以下に収まる() {
    assert_eq!(窓の係数(0.0), 1.0);
    for 刻み in 0..=200u32 {
        let 係数 = 窓の係数(単精度へ狭める(f64::from(刻み) * 0.1));
        assert!((0.0..=1.0).contains(&係数), "窓が値域を外れた: {係数}");
    }
}

/// 半径の1割より手前では比の4乗が1e-4を下回り、1から引いた差が単精度の刻みに埋もれて窓は1のまま平らになる。
/// そのため厳密に減ることを求めるのは半径の1割から先だけとし、全域では増えないことを求める。
#[test]
fn 窓は距離が伸びるほど小さくなる() {
    let mut 直前 = 窓の係数(0.0);
    for 刻み in 1..=100u32 {
        let 係数 = 窓の係数(単精度へ狭める(f64::from(刻み) * 0.1));
        assert!(係数 <= 直前, "窓が距離{刻み}で増えた: {直前} から {係数}");
        if 刻み >= 10 {
            assert!(係数 < 直前, "窓が距離{刻み}で減らなかった: {直前} から {係数}");
        }
        直前 = 係数;
    }
}

#[test]
fn 同じ入力からは同じ窓を返す() {
    for 刻み in 0..=120u32 {
        let 距離 = メートル::生成する(単精度へ狭める(f64::from(刻み) * 0.1));
        let 窓 = 減衰の窓::距離と影響半径から求める(距離, 半径10メートル());
        assert_eq!(窓, 減衰の窓::距離と影響半径から求める(距離, 半径10メートル()));
    }
}

#[test]
fn 影響半径は有限かつ正でなければ作れない() {
    assert!(影響半径::生成する(メートル::生成する(0.0)).is_err());
    assert!(影響半径::生成する(メートル::生成する(-1.0)).is_err());
    assert!(影響半径::生成する(メートル::生成する(f32::INFINITY)).is_err());
    assert!(影響半径::生成する(メートル::生成する(f32::NAN)).is_err());
}
