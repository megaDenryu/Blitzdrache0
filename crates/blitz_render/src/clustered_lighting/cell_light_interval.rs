//! 1つのセルが持つ、クラスタ光添字列の区間という量。触れる状態を持たず、担うのは選別が書いた開始位置と件数の保持である。
//!
//! 開始位置を保持して導出しないのは、選別の取り方(セルごとに同じ長さを割り当てる)が変わったときに、
//! 読み戻した値と導出した値が食い違うことをこの型で見つけられるようにするためである。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct セルの光の区間 {
    開始位置: u32,
    件数: u32,
}

impl セルの光の区間 {
    pub fn 生成する(開始位置: u32, 件数: u32) -> Self {
        Self { 開始位置, 件数 }
    }

    pub(super) fn 開始位置(self) -> u32 {
        self.開始位置
    }

    pub(super) fn 件数(self) -> u32 {
        self.件数
    }
}
