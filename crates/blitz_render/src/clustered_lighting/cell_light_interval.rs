//! 1つのセルが持つ、クラスタ光添字列の区間という量。触れる状態を持たず、担うのは選別が書いた開始位置と件数の保持である。
//!
//! 開始位置を保持して導出しないのは、選別の取り方(セルごとに同じ長さを割り当てる)が変わったときに、
//! 読み戻した値と導出した値が食い違うことをこの型で見つけられるようにするためである。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct セルの光の区間 {
    開始位置: u32,
    件数: u32,
}

impl セルの光の区間 {
    pub fn 生成する(開始位置: u32, 件数: u32) -> Self {
        Self { 開始位置, 件数 }
    }

    pub(super) fn 開始位置(self) -> u32 {
        self.開始位置
    }

    pub(super) fn 件数(self) -> u32 {
        self.件数
    }

    /// 選別が使う取り方(セルごとに同じ長さの区間を割り当てる)にこの区間が従っているか。
    /// 従っていなければ、読み戻したバイト列がGPU側の書式と食い違っているか、選別の取り方が変わっている。
    pub(super) fn 取り方に従うか(self, 一次元の添字: u32, セル1つの上限件数: u32) -> 区間の書式の検査結果 {
        if self.開始位置 != 一次元の添字 * セル1つの上限件数 {
            return 区間の書式の検査結果::開始位置が取り方と違う {
                期待値: 一次元の添字 * セル1つの上限件数,
            };
        }
        if self.件数 > セル1つの上限件数 {
            return 区間の書式の検査結果::件数が上限を超えた;
        }
        区間の書式の検査結果::取り方どおり
    }
}

/// 区間がGPU側の書式に従っているかの答え。破れの種類で呼び出し側が別のエラーを組み立てるため、真偽でなく判別共用体で返す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 区間の書式の検査結果 {
    取り方どおり,
    開始位置が取り方と違う { 期待値: u32 },
    件数が上限を超えた,
}
