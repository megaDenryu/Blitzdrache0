//! 点光源の放射の反証の検査。期待値は放射の式を通さず、手で解いた数から独立に作る。
//! 実装を呼び戻して期待値を作ると、式を書き換えた誤りが検査を素通りする。
//! 減衰の窓そのものの反証は`attenuation_tests.rs`が持つ。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use crate::lighting_input::光強度;

use super::influence_radius::影響半径;
use super::narrowing::単精度へ狭める;
use super::point_light_radiance::点光源の放射;

fn 半径10メートル() -> 影響半径 {
    影響半径::生成する(メートル::生成する(10.0)).unwrap()
}

fn 放射の値(距離: f32, 強度: f32) -> f32 {
    点光源の放射::距離と強度と影響半径から求める(メートル::生成する(距離), 光強度::生成する(強度).unwrap(), 半径10メートル()).値()
}

/// 半径10メートル・距離5メートルでは比が0.5、その4乗が0.0625、窓は0.9375の2乗で0.87890625である。
/// 強度100の逆二乗は微小量を無視すると4.0であり、積は3.515625になる。
#[test]
fn 放射は逆二乗と窓の積である() {
    let 放射 = 放射の値(5.0, 100.0);
    assert!((放射 - 3.515_625).abs() < 1.0e-4, "放射が手計算と合わない: {放射}");
}

#[test]
fn 放射は影響半径の外で0になる() {
    assert_eq!(放射の値(12.0, 100.0), 0.0);
}

/// 光の位置にちょうど載った表面では光へ向かう向きが定まらず、どの反射の式も寄与を作れない。
/// GPU側の写し(`shaders/local_light_shading.slang`)も同じ距離で標本を1つも行わずに向きも放射も0で返すため、
/// ここで0でない値を返すと、正本と写しが光の芯だけで食い違う。
#[test]
fn 放射は距離0で0になる() {
    assert_eq!(放射の値(0.0, 100.0), 0.0);
}

#[test]
fn 同じ入力からは同じ放射を返す() {
    for 刻み in 0..=120u32 {
        let 距離 = 単精度へ狭める(f64::from(刻み) * 0.1);
        assert_eq!(放射の値(距離, 7.5), 放射の値(距離, 7.5));
    }
}
