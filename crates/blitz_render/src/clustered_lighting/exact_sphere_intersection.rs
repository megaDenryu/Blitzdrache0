//! 局所光の影響範囲の球がセルの錐台と実際に交わるかの厳密な判定。受け取るのは球、返すのは交わるかである。
//!
//! 保守的な判定(`sphere_intersection`の`球と交わりうるか`)と別に置くのは、あちらが稜と角の近くで
//! 交わらない球を交わると答えるためである。あちらは絵の欠損を出さないことを優先して費用の側へ倒してあり、
//! この厳密な判定はその費用がどれだけ出ているか(偽陽性の率)を測る基準として使う。
//!
//! 求め方は、中心が錐台の内側なら交わる、外側なら錐台の境界(6つの四角形)までの最短距離が半径以内なら交わる、である。
//! 錐台は凸であるため、外側の点から見た最短距離は境界までの最短距離と等しい。
//!
//! 注意: この判定は選別の実装が読むものではない。読むのは検収の側だけであり、毎フレームの経路は保守的な判定だけを通る。

use super::cell_face_quad;
use super::cell_frustum::クラスタ格子のセルの錐台;
use super::light_sphere::局所光の影響範囲の球;
use super::quad_distance::点から凸四角形までの距離の二乗;

impl クラスタ格子のセルの錐台 {
    pub fn 球と実際に交わるか(self, 球: 局所光の影響範囲の球) -> bool {
        if self.位置を含むか(球.中心()) {
            return true;
        }
        let 半径 = 球.半径().長さ().値();
        let 半径の二乗 = 半径 * 半径;
        cell_face_quad::六面を並べる(self)
            .iter()
            .any(|四隅| 点から凸四角形までの距離の二乗(球.中心(), 四隅) <= 半径の二乗)
    }
}
