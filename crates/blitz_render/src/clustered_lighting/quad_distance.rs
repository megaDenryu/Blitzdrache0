//! ビュー空間の1点から、平面の凸四角形までの最短距離の二乗を求める工程。受け取るのは点と四隅、返すのは距離の二乗である。
//!
//! 距離そのものでなく二乗を返すのは、比べる相手が半径の二乗であり、平方根を取らずに済むためである。
//!
//! 求め方は2段である。点を四角形の平面へ落とし、落ちた先が四角形の内側なら平面までの距離がそのまま答えになる。
//! 外側なら、4つの辺の線分までの距離の最小が答えになる。凸多角形ではこの2つで場合が尽きる。
//!
//! 内側の判定を4辺の外積の符号で行うのは、四隅が巡回の順に並ぶ前提があるためである(`cell_face_quad`が並べる)。
//! 巡回でない並びを渡すと、交差した四辺形の内側を判定することになり答えが変わる。
//!
//! 生の数学型(glam)を内側だけで使うのは、ここが値オブジェクトの外へ出ない純粋な幾何の計算だからである。
//! 境界での型はビュー空間の位置であり、生の型は関数の外へ1つも出ない。

use blitz_math::{ビュー, 位置};
use glam::Vec3;

use super::cell_face_quad::面の四隅;

pub(super) fn 点から凸四角形までの距離の二乗(点: 位置<ビュー>, 四隅: &面の四隅) -> f32 {
    let 点 = ベクトルへ写す(点);
    let 隅: [Vec3; 4] = std::array::from_fn(|添字| ベクトルへ写す(四隅[添字]));
    let 法線 = (隅[1] - 隅[0]).cross(隅[3] - 隅[0]);
    let 法線の長さ二乗 = 法線.length_squared();
    if 法線の長さ二乗 > 0.0 && 平面へ落とした先が内側か(点, &隅, 法線) {
        let 平面までの符号付き距離 = (点 - 隅[0]).dot(法線);
        return 平面までの符号付き距離 * 平面までの符号付き距離 / 法線の長さ二乗;
    }
    四辺までの距離の二乗の最小(点, &隅)
}

/// 点を平面へ落とした先が四角形の内側にあるか。4つの辺について、辺から点へ向かう外積が法線と同じ向きであることを見る。
/// 境界の上は内側とみなす。
fn 平面へ落とした先が内側か(点: Vec3, 隅: &[Vec3; 4], 法線: Vec3) -> bool {
    (0..4).all(|添字| {
        let 始点 = 隅[添字];
        let 終点 = 隅[(添字 + 1) % 4];
        (終点 - 始点).cross(点 - 始点).dot(法線) >= 0.0
    })
}

fn 四辺までの距離の二乗の最小(点: Vec3, 隅: &[Vec3; 4]) -> f32 {
    (0..4)
        .map(|添字| 線分までの距離の二乗(点, 隅[添字], 隅[(添字 + 1) % 4]))
        .fold(f32::INFINITY, f32::min)
}

fn 線分までの距離の二乗(点: Vec3, 始点: Vec3, 終点: Vec3) -> f32 {
    let 辺 = 終点 - 始点;
    let 辺の長さ二乗 = 辺.length_squared();
    if 辺の長さ二乗 <= 0.0 {
        return (点 - 始点).length_squared();
    }
    let 媒介変数 = ((点 - 始点).dot(辺) / 辺の長さ二乗).clamp(0.0, 1.0);
    (点 - (始点 + 辺 * 媒介変数)).length_squared()
}

fn ベクトルへ写す(位置: 位置<ビュー>) -> Vec3 {
    Vec3::new(位置.x().値(), 位置.y().値(), 位置.z().値())
}
