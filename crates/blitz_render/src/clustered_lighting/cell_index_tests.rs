//! セル添字と分割数の反証の検査。3軸と一次元の往復・格子の外の拒否・分割数の値域に加えて、
//! セル添字を検証した分割数がその添字に付いて回ることを見る。
//!
//! 分割数の同一性を見るのは、これが失われると「一次元の添字は必ずセルの総数より小さい」という
//! クラスタ光添字列を引くための公開契約が、呼び出し規律だけの申し送りになるためである。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use crate::extent::ウィンドウ寸法;

use super::cell_index::クラスタ格子のセル添字;
use super::cell_mapping::クラスタ写像;
use super::depth_range::クラスタの奥行き範囲;
use super::grid_division::クラスタ格子の分割数;
use super::half_field_of_view_tangent::視野の半角の正接;
use super::test_fixture::{検査用のクラスタ写像, 検査用のセル添字を作る};

fn 分割が1つだけの写像() -> クラスタ写像 {
    クラスタ写像::生成する(
        クラスタ格子の分割数::生成する(1, 1, 1).unwrap(),
        ウィンドウ寸法::生成する(64, 64),
        クラスタの奥行き範囲::生成する(メートル::生成する(0.1), メートル::生成する(200.0)).unwrap(),
        視野の半角の正接::生成する(0.75, 0.4).unwrap(),
    )
    .unwrap()
}

#[test]
fn 一次元の添字は3軸の添字と往復する() {
    let 分割数 = クラスタ格子の分割数::仮置きの分割数を返す();
    for 一次元 in 0..分割数.セルの総数() {
        let 添字 = クラスタ格子のセル添字::一次元の添字から戻す(一次元, 分割数).unwrap();
        assert_eq!(添字.一次元の添字へ畳む(), 一次元);
    }
}

/// 添字は自分を検証した分割数を持ち歩くため、畳むときに別の分割数を渡す余地が無い。16×8×24で検証した
/// 添字を1×1×1で畳んでセルの総数を超える値を返す、という壊し方が型として作れないことを見る。
#[test]
fn どのセル添字を畳んでも自分の格子のセルの総数より小さい() {
    let 分割数 = クラスタ格子の分割数::仮置きの分割数を返す();
    for 一次元 in 0..分割数.セルの総数() {
        let 添字 = クラスタ格子のセル添字::一次元の添字から戻す(一次元, 分割数).unwrap();
        assert_eq!(添字.分割数(), 分割数);
        assert!(添字.一次元の添字へ畳む() < 添字.分割数().セルの総数());
    }
}

/// 別の分割数で検証した添字を渡された写像は、格子の外のタイルの区間を導かずに型付きエラーで拒む。
#[test]
fn 別の分割数で検証したセル添字を写像は拒む() {
    let 添字 = 検査用のセル添字を作る(15, 7, 23);
    assert!(分割が1つだけの写像().セルの錐台を求める(添字).is_err());
    assert!(検査用のクラスタ写像().セルの錐台を求める(添字).is_ok());
}

#[test]
fn 格子の外のセル添字は作れない() {
    let 分割数 = クラスタ格子の分割数::仮置きの分割数を返す();
    assert!(クラスタ格子のセル添字::生成する(分割数.横(), 0, 0, 分割数).is_err());
    assert!(クラスタ格子のセル添字::生成する(0, 分割数.縦(), 0, 分割数).is_err());
    assert!(クラスタ格子のセル添字::生成する(0, 0, 分割数.奥行き(), 分割数).is_err());
    assert!(クラスタ格子のセル添字::一次元の添字から戻す(分割数.セルの総数(), 分割数).is_err());
}

#[test]
fn 分割数は各軸が1以上でなければ作れない() {
    assert!(クラスタ格子の分割数::生成する(0, 8, 24).is_err());
    assert!(クラスタ格子の分割数::生成する(16, 0, 24).is_err());
    assert!(クラスタ格子の分割数::生成する(16, 8, 0).is_err());
    assert_eq!(
        クラスタ格子の分割数::生成する(16, 8, 24).unwrap(),
        クラスタ格子の分割数::仮置きの分割数を返す()
    );
}
