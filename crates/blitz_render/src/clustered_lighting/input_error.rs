//! クラスタ多光源の値オブジェクトが生成のときに入力を拒む理由。触れる状態を持たず、担うのは拒否の理由の
//! 列挙と、拒んだ値をそのまま文面へ載せることである。どの値をどの理由で拒むかは各値オブジェクトの
//! `生成する`が決める。
//!
//! 型ごとに列挙を分けず1つへまとめるのは、影響半径・打ち切りの閾値・奥行き範囲・分割数・視野の半角の正接が
//! どれも「有限か」「正か」「順序が正しいか」という同じ3種の検証しか持たないためである
//! (`crates/blitz_render/src/lighting_input/components.rs`が同じ形を採っている)。

use thiserror::Error;

use super::grid_division::クラスタ格子の分割数;

#[derive(Debug, Clone, Copy, Error, PartialEq)]
pub enum クラスタ多光源入力エラー {
    #[error("影響半径は有限かつ正でなければならない: {0}")]
    影響半径不正(f32),
    #[error("打ち切りの閾値は有限かつ正でなければならない: {0}")]
    打ち切りの閾値不正(f32),
    #[error("クラスタの奥行き範囲は近と遠がともに有限かつ正で、近が遠より手前でなければならない: 近{近} 遠{遠}")]
    奥行き範囲不正 { 近: f32, 遠: f32 },
    #[error("クラスタ格子の分割数は各軸とも1以上で、積が符号なし32ビットに収まらなければならない: 横{横} 縦{縦} 奥行き{奥行き}")]
    分割数不正 { 横: u32, 縦: u32, 奥行き: u32 },
    #[error("視野の半角の正接は横と縦がともに有限かつ正でなければならない: 横{横} 縦{縦}")]
    視野の半角の正接不正 { 横: f32, 縦: f32 },
    #[error("クラスタ写像の画面の寸法は横と縦がともに1以上でなければならない: 横{横} 縦{縦}")]
    画面の寸法不正 { 横: u32, 縦: u32 },
    #[error("セル添字が格子の外にある: 横{横} 縦{縦} 奥行き{奥行き}")]
    セル添字が格子の外 { 横: u32, 縦: u32, 奥行き: u32 },
    #[error("一次元のセル添字が格子の外にある: {0}")]
    一次元のセル添字が格子の外(u32),
    #[error("セル添字を検証した分割数がクラスタ写像の分割数と違う: 添字側{添字側:?} 写像側{写像側:?}")]
    セル添字の分割数が写像と違う {
        添字側: クラスタ格子の分割数,
        写像側: クラスタ格子の分割数,
    },
    #[error("局所光の影響範囲の球の中心は全成分が有限でなければならない: {0:?}")]
    光の中心位置不正([f32; 3]),
    #[error("読み戻した区間表の件数が格子のセルの総数と違う: 件数{件数} 期待値{期待値}")]
    読み戻した区間表の件数が格子と違う { 件数: u32, 期待値: u32 },
    #[error("読み戻したクラスタ光添字列の要素数が格子と違う: 要素数{要素数} 期待値{期待値}")]
    読み戻した光添字列の要素数が格子と違う { 要素数: u32, 期待値: u32 },
    #[error("割り当ての区間がクラスタ光添字列の外を指している: {0}")]
    割り当ての区間が光添字列の外(u32),
    #[error("割り当てられた光の添字が宣言した件数の外にある: {0}")]
    割り当てられた光の添字が宣言の外(u32),
    #[error("読み戻した区間の開始位置が取り方と違う: セル{一次元の添字} 開始位置{開始位置} 期待値{期待値}")]
    読み戻した区間の開始位置が取り方と違う {
        一次元の添字: u32, 開始位置: u32, 期待値: u32
    },
    #[error("読み戻した区間の件数がセル1つの上限を超えた: セル{一次元の添字} 件数{件数} 上限{上限}")]
    読み戻した区間の件数が上限を超えた { 一次元の添字: u32, 件数: u32, 上限: u32 },
}
