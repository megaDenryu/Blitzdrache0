//! 選別が書いた割り当てを、写像と光の球へ突き合わせて数える工程。受け取るのは写像とビュー空間の球の並びと
//! 読み戻した区間表と添字列、返すのは割り当ての統計である。
//!
//! 数えるのは4つである。光を1件以上持つセルの数、割り当ての総件数、セルあたりの最大件数、そして
//! 厳密な交差判定でも交わる割り当ての件数である。最後の1つが保守的な判定の偽陽性を測る基準になる。
//!
//! この工程を検収の側でなくCPU正本の層へ置くのは、写像もセルの錐台も球との交差もこの層が正本を持つためである。
//! 検収の側へ写しを置くと、その写しの正しさが検収の前提になる。
//!
//! 読み戻したものがGPU側の書式に従っているかの検査は`assignment_readback_check`が持つ。

use super::assignment_readback_check::{区間の書式を確かめる, 長さを確かめる};
use super::assignment_statistics::クラスタ選別の割り当て統計;
use super::assignment_tally::割り当ての数え;
use super::cell_index::クラスタ格子のセル添字;
use super::cell_light_capacity::クラスタ光添字列の要素数;
use super::cell_light_interval::セルの光の区間;
use super::cell_mapping::クラスタ写像;
use super::input_error::クラスタ多光源入力エラー;
use super::light_sphere::局所光の影響範囲の球;

pub fn 割り当てを突き合わせて統計を作る(
    写像: クラスタ写像,
    球一覧: &[局所光の影響範囲の球],
    区間一覧: &[セルの光の区間],
    光添字列: &[u32],
) -> Result<クラスタ選別の割り当て統計, クラスタ多光源入力エラー> {
    let 分割数 = 写像.分割数();
    長さを確かめる(
        区間一覧.len(),
        配列添字へ写す(分割数.セルの総数()),
        光添字列.len(),
        クラスタ光添字列の要素数(分割数),
    )?;
    let mut 数え = 割り当ての数え::空で始める();
    for (走査位置, 区間) in 区間一覧.iter().enumerate() {
        let 一次元の添字 = 添字へ写す(走査位置);
        区間の書式を確かめる(*区間, 一次元の添字)?;
        数え.区間を数える(*区間);
        let 添字 = クラスタ格子のセル添字::一次元の添字から戻す(一次元の添字, 分割数)?;
        let 錐台 = 写像.セルの錐台を求める(添字)?;
        for 位置 in 0..区間.件数() {
            let 光の添字 = 光添字列を引く(光添字列, 区間.開始位置() + 位置)?;
            let 球 = 球一覧
                .get(配列添字へ写す(光の添字))
                .ok_or(クラスタ多光源入力エラー::割り当てられた光の添字が宣言の外(
                    光の添字,
                ))?;
            if 錐台.球と実際に交わるか(*球) {
                数え.厳密にも交わる1件を数える();
            }
        }
    }
    Ok(数え.統計へ写す(分割数.セルの総数(), 件数へ写す(球一覧.len())))
}

fn 光添字列を引く(光添字列: &[u32], 位置: u32) -> Result<u32, クラスタ多光源入力エラー> {
    光添字列
        .get(配列添字へ写す(位置))
        .copied()
        .ok_or(クラスタ多光源入力エラー::割り当ての区間が光添字列の外(位置))
}

/// 前提: 対応する型はこの環境で必ず収まる(セルの総数は符号なし32ビット、配列の長さは同じ桁である)。
fn 配列添字へ写す(値: u32) -> usize {
    usize::try_from(値).unwrap_or_else(|_| panic!("セルの総数がusizeに収まらないという不変条件の破れ: {値}"))
}

fn 添字へ写す(値: usize) -> u32 {
    u32::try_from(値).unwrap_or_else(|_| panic!("走査の添字が符号なし32ビットに収まらないという不変条件の破れ: {値}"))
}

fn 件数へ写す(値: usize) -> u32 {
    u32::try_from(値).unwrap_or_else(|_| panic!("数えた件数が符号なし32ビットに収まらないという不変条件の破れ: {値}"))
}
