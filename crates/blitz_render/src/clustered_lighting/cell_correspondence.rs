//! 画面の画素およびビュー空間の奥行きと、クラスタ格子のセルの対応を両方向で配る工程。受け取るのは画素と
//! 奥行き、またはセル添字。返すのはセル添字、またはそのセルが占めるビュー空間の錐台である。
//!
//! 往復の2方向を1つのファイルへ置くのは、どちらもクラスタ写像の同じ4つのパラメータだけを読み、軸ごとの
//! 境界の規約を`screen_tile`と`depth_slice`の同じ関数から取るためである。片方だけを直すと、光を割り当てた
//! セルと画素段が読むセルが食い違い、絵にしか出ない。
//!
//! 触れるのはクラスタ写像の4つのパラメータだけであり、格子の中身も光も知らない。

use blitz_math::メートル;

use super::cell_frustum::クラスタ格子のセルの錐台;
use super::cell_index::クラスタ格子のセル添字;
use super::cell_mapping::クラスタ写像;
use super::depth_slice;
use super::input_error::クラスタ多光源入力エラー;
use super::interval::区間;
use super::screen_tile;

impl クラスタ写像 {
    /// 画面の画素とビュー空間の奥行きが落ちるセル。画面の外の画素も範囲の外の奥行きも端のセルへ入れるため、
    /// どの入力もちょうど1つのセルへ落ちる。
    pub fn 画面の画素とビュー空間の奥行きからセル添字を求める(
        self,
        画素の横: u32,
        画素の縦: u32,
        奥行き: メートル,
    ) -> クラスタ格子のセル添字 {
        let 横 = screen_tile::画素からタイルの添字を求める(画素の横, self.画面の寸法().幅(), self.分割数().横());
        let 縦 = screen_tile::画素からタイルの添字を求める(画素の縦, self.画面の寸法().高さ(), self.分割数().縦());
        let 奥行きの段 = depth_slice::奥行きから段の添字を求める(奥行き, self.奥行き範囲(), self.分割数().奥行き());
        match クラスタ格子のセル添字::生成する(横, 縦, 奥行きの段, self.分割数()) {
            Ok(添字) => 添字,
            // 軸ごとの写像は分割数より小さい添字だけを返すため、この枝はプログラムのバグでしか到達しない。
            Err(理由) => panic!("軸ごとの写像が分割数の内側を返すという不変条件が破れた: {理由}"),
        }
    }

    /// セルが占めるビュー空間の錐台。正規化装置座標の縦は下が正であり、ビュー空間の縦は上が正であるため、
    /// 縦の傾きは符号が反転して上下の順序も入れ替わる。
    ///
    /// 別の分割数で検証した添字を拒むのは、その添字の各軸がこの写像の分割数の内側にある保証が無く、
    /// 受け入れると格子の外のタイルの区間を導いてしまうためである。
    pub fn セルの錐台を求める(
        self,
        添字: クラスタ格子のセル添字,
    ) -> Result<クラスタ格子のセルの錐台, クラスタ多光源入力エラー> {
        if 添字.分割数() != self.分割数() {
            return Err(クラスタ多光源入力エラー::セル添字の分割数が写像と違う {
                添字側: 添字.分割数(),
                写像側: self.分割数(),
            });
        }
        let 横の座標 = screen_tile::タイルの添字から正規化装置座標の区間を求める(添字.横(), self.分割数().横());
        let 縦の座標 = screen_tile::タイルの添字から正規化装置座標の区間を求める(添字.縦(), self.分割数().縦());
        let 横の正接 = self.視野の半角の正接().横();
        let 縦の正接 = self.視野の半角の正接().縦();
        Ok(クラスタ格子のセルの錐台::生成する(
            depth_slice::段の添字から奥行きの区間を求める(添字.奥行き(), self.奥行き範囲(), self.分割数().奥行き()),
            区間::生成する(横の座標.下限() * 横の正接, 横の座標.上限() * 横の正接),
            区間::生成する(-縦の座標.上限() * 縦の正接, -縦の座標.下限() * 縦の正接),
        ))
    }
}
