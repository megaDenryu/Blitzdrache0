//! クラスタ格子のセルを指す添字という量と、3軸の添字と1本の添字の往復。触れる状態を持たず、担うのは
//! 3軸それぞれが分割数の内側にあることの保証と、並びの規約の保持である。
//!
//! 検証に使った分割数を添字が自分で持つのは、一次元へ畳むときに別の分割数を渡せないようにするためである。
//! 分割数を畳む側の引数で受けると、16×8×24で検証した添字を1×1×1で畳んでセルの総数を超える値を返せてしまい、
//! 「クラスタ光添字列の区間表を引ける添字である」という公開契約が呼び出し規律だけの申し送りになる。
//!
//! 往復の2方向を1つのファイルへ置くのは、どちらも同じ1つの規約(横が最も速く変わり、次に縦、最後に奥行き)を
//! 使うためである。片方だけを直すと、選別が書いたセルと画素段が読むセルが食い違い、絵にしか出ない。

use super::grid_division::クラスタ格子の分割数;
use super::input_error::クラスタ多光源入力エラー;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct クラスタ格子のセル添字 {
    横: u32,
    縦: u32,
    奥行き: u32,
    分割数: クラスタ格子の分割数,
}

impl クラスタ格子のセル添字 {
    pub fn 生成する(
        横: u32, 縦: u32, 奥行き: u32, 分割数: クラスタ格子の分割数
    ) -> Result<Self, クラスタ多光源入力エラー> {
        if 横 >= 分割数.横() || 縦 >= 分割数.縦() || 奥行き >= 分割数.奥行き() {
            return Err(クラスタ多光源入力エラー::セル添字が格子の外 { 横, 縦, 奥行き });
        }
        Ok(Self {
            横, 縦, 奥行き, 分割数
        })
    }

    pub fn 横(self) -> u32 {
        self.横
    }

    pub fn 縦(self) -> u32 {
        self.縦
    }

    pub fn 奥行き(self) -> u32 {
        self.奥行き
    }

    /// この添字を検証した分割数。クラスタ写像は自分の分割数とこれが等しいことを確かめてから錐台を導く。
    pub fn 分割数(self) -> クラスタ格子の分割数 {
        self.分割数
    }

    /// クラスタ光添字列の区間表を引くための1本の添字。値は必ずセルの総数より小さい。
    pub fn 一次元の添字へ畳む(self) -> u32 {
        (self.奥行き * self.分割数.縦() + self.縦) * self.分割数.横() + self.横
    }

    pub fn 一次元の添字から戻す(
        添字: u32, 分割数: クラスタ格子の分割数
    ) -> Result<Self, クラスタ多光源入力エラー> {
        if 添字 >= 分割数.セルの総数() {
            return Err(クラスタ多光源入力エラー::一次元のセル添字が格子の外(添字));
        }
        Ok(Self {
            横: 添字 % 分割数.横(),
            縦: (添字 / 分割数.横()) % 分割数.縦(),
            奥行き: 添字 / (分割数.横() * 分割数.縦()),
            分割数,
        })
    }
}
