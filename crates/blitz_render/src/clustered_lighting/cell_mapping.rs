//! クラスタ写像という、格子の形を決める4つのパラメータの持ち主。担うのはパラメータの不変条件の保証と、
//! 画面の画素および奥行きとセルの対応を両方向で配ることである。
//!
//! 4つを1つの型へ束ねるのは、画素段と選別のコンピュートの両方が同じ4つを読む必要があり、別々に持つと
//! 片方だけを直した食い違いが絵にしか出ないためである。軸ごとの境界の規約は`screen_tile`と`depth_slice`が
//! 持ち、この型は2つの軸を組み合わせるだけである。
//! 参照: `_doc/設計/クラスタ多光源と点光源の影.md`

use blitz_math::メートル;

use crate::extent::ウィンドウ寸法;

use super::cell_frustum::クラスタ格子のセルの錐台;
use super::cell_index::クラスタ格子のセル添字;
use super::depth_range::クラスタの奥行き範囲;
use super::depth_slice;
use super::grid_division::クラスタ格子の分割数;
use super::half_field_of_view_tangent::視野の半角の正接;
use super::input_error::クラスタ多光源入力エラー;
use super::interval::区間;
use super::screen_tile;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct クラスタ写像 {
    分割数: クラスタ格子の分割数,
    画面の寸法: ウィンドウ寸法,
    奥行き範囲: クラスタの奥行き範囲,
    視野の半角の正接: 視野の半角の正接,
}

impl クラスタ写像 {
    pub fn 生成する(
        分割数: クラスタ格子の分割数,
        画面の寸法: ウィンドウ寸法,
        奥行き範囲: クラスタの奥行き範囲,
        視野の半角の正接: 視野の半角の正接,
    ) -> Result<Self, クラスタ多光源入力エラー> {
        if 画面の寸法.ゼロ寸法か() {
            return Err(クラスタ多光源入力エラー::画面の寸法不正 {
                横: 画面の寸法.幅(),
                縦: 画面の寸法.高さ(),
            });
        }
        Ok(Self {
            分割数,
            画面の寸法,
            奥行き範囲,
            視野の半角の正接,
        })
    }

    pub fn 分割数(self) -> クラスタ格子の分割数 {
        self.分割数
    }

    pub fn 画面の寸法(self) -> ウィンドウ寸法 {
        self.画面の寸法
    }

    pub fn 奥行き範囲(self) -> クラスタの奥行き範囲 {
        self.奥行き範囲
    }

    pub fn 視野の半角の正接(self) -> 視野の半角の正接 {
        self.視野の半角の正接
    }

    /// 画面の画素とビュー空間の奥行きが落ちるセル。画面の外の画素も範囲の外の奥行きも端のセルへ入れるため、
    /// どの入力もちょうど1つのセルへ落ちる。
    pub fn 画面の画素とビュー空間の奥行きからセル添字を求める(
        self,
        画素の横: u32,
        画素の縦: u32,
        奥行き: メートル,
    ) -> クラスタ格子のセル添字 {
        let 横 = screen_tile::画素からタイルの添字を求める(画素の横, self.画面の寸法.幅(), self.分割数.横());
        let 縦 = screen_tile::画素からタイルの添字を求める(画素の縦, self.画面の寸法.高さ(), self.分割数.縦());
        let 奥行きの段 = depth_slice::奥行きから段の添字を求める(奥行き, self.奥行き範囲, self.分割数.奥行き());
        match クラスタ格子のセル添字::生成する(横, 縦, 奥行きの段, self.分割数) {
            Ok(添字) => 添字,
            // 軸ごとの写像は分割数より小さい添字だけを返すため、この枝はプログラムのバグでしか到達しない。
            Err(理由) => panic!("軸ごとの写像が分割数の内側を返すという不変条件が破れた: {理由}"),
        }
    }

    /// セルが占めるビュー空間の錐台。正規化装置座標の縦は下が正であり、ビュー空間の縦は上が正であるため、
    /// 縦の傾きは符号が反転して上下の順序も入れ替わる。
    pub fn セルの錐台を求める(self, 添字: クラスタ格子のセル添字) -> クラスタ格子のセルの錐台 {
        let 横の座標 = screen_tile::タイルの添字から正規化装置座標の区間を求める(添字.横(), self.分割数.横());
        let 縦の座標 = screen_tile::タイルの添字から正規化装置座標の区間を求める(添字.縦(), self.分割数.縦());
        let 横の正接 = self.視野の半角の正接.横();
        let 縦の正接 = self.視野の半角の正接.縦();
        クラスタ格子のセルの錐台::生成する(
            depth_slice::段の添字から奥行きの区間を求める(添字.奥行き(), self.奥行き範囲, self.分割数.奥行き()),
            区間::生成する(横の座標.下限() * 横の正接, 横の座標.上限() * 横の正接),
            区間::生成する(-縦の座標.上限() * 縦の正接, -縦の座標.下限() * 縦の正接),
        )
    }
}
