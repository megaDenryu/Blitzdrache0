//! 点光源の放射という量そのもの。触れる状態を持たず、担うのは`強度 / (距離の二乗 + 微小量)`へ減衰の窓を
//! 掛けるという1つの式の保持である。色を掛ける前の大きさであり、色は消費する側が掛ける。
//!
//! 微小量を距離の二乗へ足すのは、光の位置に載った表面で放射が無限大になるのを防ぐためである。値を
//! 1e-8としたのは、現行のシェーダーが距離を1e-4メートルで下から抑えており(`shaders/direct_light_shading.slang`)、
//! その二乗と一致させると光の芯での上限が変わらないためである。
//! 参照: `_doc/設計/クラスタ多光源と点光源の影.md`

use blitz_math::メートル;

use crate::lighting_input::光強度;

use super::attenuation_window::減衰の窓;
use super::influence_radius::影響半径;

/// 距離の二乗へ足す微小量。長さの二乗の次元を持ち、単位はメートルの二乗である。
pub(super) const 距離の二乗へ足す微小量: f32 = 1e-8;

/// 1件の点光源が表面へ与える、色を掛ける前の放射の大きさ。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 点光源の放射(f32);

impl 点光源の放射 {
    /// 前提: 呼び出し元は距離として有限で0以上の長さを与える。
    pub fn 距離と強度と影響半径から求める(距離: メートル, 強度: 光強度, 影響半径: 影響半径) -> Self {
        let 窓 = 減衰の窓::距離と影響半径から求める(距離, 影響半径);
        let 距離の二乗 = 距離.値() * 距離.値();
        let 逆二乗の放射 = 強度.値() / (距離の二乗 + 距離の二乗へ足す微小量);
        Self(逆二乗の放射 * 窓.係数())
    }

    pub fn 値(self) -> f32 {
        self.0
    }
}
