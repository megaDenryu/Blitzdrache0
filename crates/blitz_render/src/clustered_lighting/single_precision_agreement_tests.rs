//! 正本と単精度の写しが同じセルを答えるかの反証。第1段階が`depth_slice`の冒頭へ残した宿題(段の境界の
//! 近傍で正本と写しの段が分かれうる)へ、実測で答えを付ける。
//!
//! 確かめるのは4つである。タイルの添字が全画素で完全に一致すること、段の添字の食い違いが境界の近傍でも
//! 1段までに収まること、写しが選んだ段の区間が余裕込みでその奥行きを必ず含むこと、画素の中心の正規化装置座標が
//! 余裕込みでそのタイルの区間へ必ず入ることである。後ろの2つが、選別が光を落とさないことの根拠になる。

use blitz_math::メートル;

use super::cell_boundary_margin::{セルの奥行きを広げる相対量, セルの横と縦を広げる画素数};
use super::single_precision_sample::{
    奥行きの分割数, 奥行き範囲, 検査する奥行き一覧, 画素の中心の正規化装置座標, 画素数と分割数の組一覧, 近, 遠
};
use super::single_precision_transcript::{
    単精度で奥行きから段の添字を求める, 単精度で選別が使うタイルの区間を求める, 単精度で選別が使う段の奥行きの区間を求める,
    単精度の写しで画素からタイルの添字を求める,
};
use super::{depth_slice, screen_tile};

#[test]
fn タイルの添字は正本と写しで完全に一致する() {
    for (画素数, 分割数) in 画素数と分割数の組一覧 {
        for 画素 in 0..画素数 {
            let 正本 = screen_tile::画素からタイルの添字を求める(画素, 画素数, 分割数);
            let 写し = 単精度の写しで画素からタイルの添字を求める(画素, 画素数, 分割数);
            assert_eq!(正本, 写し, "画素{画素}(画素数{画素数}・分割数{分割数})でタイルの添字が分かれた");
        }
    }
}

#[test]
fn 段の添字の食い違いは境界の近傍でも1段までに収まる() {
    let 範囲 = 奥行き範囲();
    for 奥行き in 検査する奥行き一覧() {
        let 正本 = depth_slice::奥行きから段の添字を求める(メートル::生成する(奥行き), 範囲, 奥行きの分割数);
        let 写し = 単精度で奥行きから段の添字を求める(奥行き, 近, 遠, 奥行きの分割数);
        let 差 = i64::from(正本) - i64::from(写し);
        assert!(差.abs() <= 1, "奥行き{奥行き}で段が{差}段ぶん分かれた(正本{正本}・写し{写し})");
    }
}

#[test]
fn 写しが選んだ段の区間は余裕込みでその奥行きを含む() {
    for 奥行き in 検査する奥行き一覧() {
        let 添字 = 単精度で奥行きから段の添字を求める(奥行き, 近, 遠, 奥行きの分割数);
        let 区間 = 単精度で選別が使う段の奥行きの区間を求める(添字, 近, 遠, 奥行きの分割数, セルの奥行きを広げる相対量);
        assert!(区間.0 <= 奥行き, "奥行き{奥行き}が段{添字}の下限{}を割った", 区間.0);
        assert!(奥行き <= 区間.1, "奥行き{奥行き}が段{添字}の上限{}を超えた", 区間.1);
    }
}

#[test]
fn 画素の中心は余裕込みでそのタイルの区間へ入る() {
    for (画素数, 分割数) in 画素数と分割数の組一覧 {
        for 画素 in 0..画素数 {
            let 添字 = 単精度の写しで画素からタイルの添字を求める(画素, 画素数, 分割数);
            let 区間 = 単精度で選別が使うタイルの区間を求める(添字, 分割数, 画素数, セルの横と縦を広げる画素数);
            let 中心 = 画素の中心の正規化装置座標(画素, 画素数);
            assert!(区間.0 <= 中心, "画素{画素}の中心{中心}がタイル{添字}の下限{}を割った", 区間.0);
            assert!(中心 <= 区間.1, "画素{画素}の中心{中心}がタイル{添字}の上限{}を超えた", 区間.1);
        }
    }
}
