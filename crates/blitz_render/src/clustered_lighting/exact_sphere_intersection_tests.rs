//! 厳密な交差判定の検査。確かめるのは3つである。錐台の中の球を交わると答えること、遠くの球を交わらないと答えること、
//! そして保守的な判定が真と答えた球のうち稜と角の近くのものを偽と答えること(偽陽性の実在)である。
//!
//! 保守的な判定との関係も併せて課す。厳密が真なら保守的も必ず真でなければならない。逆が成り立たない
//! (保守的だけが真になる)ことが偽陽性であり、この向きの片側性が保たれていることが「絵の欠損を出さない」根拠である。

#![allow(clippy::unwrap_used)]

use blitz_math::{ビュー, メートル, 位置};

use super::cell_frustum::クラスタ格子のセルの錐台;
use super::influence_radius::影響半径;
use super::interval::区間;
use super::light_sphere::局所光の影響範囲の球;

fn 錐台を作る(近: f32, 遠: f32, 横下: f32, 横上: f32, 縦下: f32, 縦上: f32) -> クラスタ格子のセルの錐台 {
    クラスタ格子のセルの錐台::生成する(
        区間::生成する(メートル::生成する(近), メートル::生成する(遠)),
        区間::生成する(横下, 横上),
        区間::生成する(縦下, 縦上),
    )
}

fn 球を作る(x: f32, y: f32, z: f32, 半径: f32) -> 局所光の影響範囲の球 {
    let 中心 = 位置::<ビュー>::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z));
    局所光の影響範囲の球::生成する(中心, 影響半径::生成する(メートル::生成する(半径)).unwrap()).unwrap()
}

#[test]
fn 錐台の中の球は交わる() {
    let 錐台 = 錐台を作る(10.0, 11.0, 0.9, 1.0, 0.9, 1.0);
    assert!(錐台.球と実際に交わるか(球を作る(9.5, 9.5, -10.5, 0.1)));
}

#[test]
fn 遠くの球は交わらない() {
    let 錐台 = 錐台を作る(10.0, 11.0, 0.9, 1.0, 0.9, 1.0);
    let 球 = 球を作る(100.0, 100.0, -10.5, 1.0);
    assert!(!錐台.球と実際に交わるか(球));
    assert!(!錐台.球と交わりうるか(球));
}

/// 角の外側の斜め方向へ置いた球。3つの面のどれからも半径以内でありながら、角そのものからは半径より遠い。
#[test]
fn 角の外の球で保守的な判定だけが真になる() {
    let 錐台 = 錐台を作る(10.0, 11.0, 0.9, 1.0, 0.9, 1.0);
    let 球 = 球を作る(11.0, 11.0, -9.0, 1.5);
    assert!(錐台.球と交わりうるか(球), "保守的な判定は交わりうると答えるはずである");
    assert!(!錐台.球と実際に交わるか(球), "厳密な判定は交わらないと答えるはずである");
}

/// 半径を角までの距離より大きくすれば、両方の判定が真になる。上の検査が「半径が足りないこと」を見ていることの対照である。
#[test]
fn 角へ届く半径なら両方が真になる() {
    let 錐台 = 錐台を作る(10.0, 11.0, 0.9, 1.0, 0.9, 1.0);
    let 球 = 球を作る(11.0, 11.0, -9.0, 2.0);
    assert!(錐台.球と交わりうるか(球));
    assert!(錐台.球と実際に交わるか(球));
}

/// 厳密が真なら保守的も真である。格子状に振った球で片側性を確かめる。
#[test]
fn 厳密が真なら保守的も真である() {
    let 錐台 = 錐台を作る(10.0, 14.0, -0.4, 0.3, -0.2, 0.5);
    for x in -6_i16..=6 {
        for y in -6_i16..=6 {
            for 奥行き in 6_i16..=18 {
                let 球 = 球を作る(f32::from(x), f32::from(y), -f32::from(奥行き), 1.3);
                assert!(
                    !錐台.球と実際に交わるか(球) || 錐台.球と交わりうるか(球),
                    "厳密が真で保守的が偽になった: ({x}, {y}, {奥行き})"
                );
            }
        }
    }
}
