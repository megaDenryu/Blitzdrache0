//! 画素と奥行きからセル添字を求める写像の、全域性・全射性・決定性の反証の検査。期待値は画面の寸法と
//! 分割数と奥行きの近と遠から独立に組み立て、写像の実装も錐台の導出も呼び戻さない。
//! セル添字と分割数そのものの検査は`cell_index_tests`が持つ。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use crate::extent::ウィンドウ寸法;

use super::cell_mapping::クラスタ写像;
use super::depth_range::クラスタの奥行き範囲;
use super::grid_division::クラスタ格子の分割数;
use super::half_field_of_view_tangent::視野の半角の正接;
use super::independent_construction::セルの中央へ落ちる画素と奥行き;
use super::narrowing::単精度へ狭める;
use super::test_fixture::{検査用のクラスタ写像, 検査用の一次元の添字から戻したセル添字, 画面の幅, 画面の高さ};

/// 画面の外の画素も範囲の外の奥行きも端のセルへ入り、どの入力も格子の内側の1つのセルへ落ちる。
#[test]
fn どの画素と奥行きも格子の内側のセルへ落ちる() {
    let 写像 = 検査用のクラスタ写像();
    let 分割数 = 写像.分割数();
    let 奥行き一覧 = [-1.0e6, -1.0, 0.0, 1.0e-9, 0.05, 0.1, 1.0, 199.9, 200.0, 1.0e6, f32::NAN];
    for 画素の横 in [0, 1, 959, 960, 画面の幅 - 1, 画面の幅, 画面の幅 * 3] {
        for 画素の縦 in [0, 1, 539, 540, 画面の高さ - 1, 画面の高さ, 画面の高さ * 3] {
            for 奥行き in 奥行き一覧 {
                let 添字 =
                    写像.画面の画素とビュー空間の奥行きからセル添字を求める(画素の横, 画素の縦, メートル::生成する(奥行き));
                assert!(添字.横() < 分割数.横() && 添字.縦() < 分割数.縦() && 添字.奥行き() < 分割数.奥行き());
            }
        }
    }
}

/// どのセルにも、そこへ落ちる画素と奥行きが実在する。片方の端のセルへ全部が吸われる誤りをこれが落とす。
/// 期待入力は画面の寸法・分割数・奥行きの近と遠だけから組み立て、写像も錐台の導出も呼ばない。
#[test]
fn どのセルにもそこへ落ちる入力が実在する() {
    let 写像 = 検査用のクラスタ写像();
    for 一次元 in 0..写像.分割数().セルの総数() {
        let 添字 = 検査用の一次元の添字から戻したセル添字(一次元);
        let (画素の横, 画素の縦, 奥行き) = セルの中央へ落ちる画素と奥行き(添字);
        let 落ちたセル = 写像.画面の画素とビュー空間の奥行きからセル添字を求める(画素の横, 画素の縦, 奥行き);
        assert_eq!(落ちたセル, 添字, "セル{一次元}の中央が別のセルへ落ちた");
    }
}

/// 画素も分割数も符号なし32ビットの全域を取りうる公開入力である。タイルの添字の中間の積を64ビットで作ると
/// この組で溢れ、製品ビルドでは折り返して別のセルを返す。
#[test]
fn 画素数と分割数が最大でも1つのセルへ落ち同じ答えを返す() {
    let 分割数 = クラスタ格子の分割数::生成する(u32::MAX, 1, 1).unwrap();
    let 写像 = クラスタ写像::生成する(
        分割数,
        ウィンドウ寸法::生成する(u32::MAX, 1),
        クラスタの奥行き範囲::生成する(メートル::生成する(0.1), メートル::生成する(200.0)).unwrap(),
        視野の半角の正接::生成する(0.75, 0.4).unwrap(),
    )
    .unwrap();
    for 画素の横 in [0, 1, u32::MAX / 2, u32::MAX - 1, u32::MAX] {
        let 求める = || 写像.画面の画素とビュー空間の奥行きからセル添字を求める(画素の横, 0, メートル::生成する(1.0));
        assert!(求める().横() < 分割数.横(), "画素{画素の横}が格子の外のセルへ落ちた");
        assert_eq!(求める(), 求める(), "画素{画素の横}で答えが揺れた");
    }
    assert_eq!(
        写像
            .画面の画素とビュー空間の奥行きからセル添字を求める(u32::MAX, 0, メートル::生成する(1.0))
            .横(),
        u32::MAX - 1
    );
}

#[test]
fn 同じ入力からは同じセル添字を返す() {
    let 写像 = 検査用のクラスタ写像();
    for 刻み in 0..=64u32 {
        let 画素の横 = 刻み * 29 % 画面の幅;
        let 画素の縦 = 刻み * 17 % 画面の高さ;
        let 奥行き = メートル::生成する(単精度へ狭める(0.1 + f64::from(刻み) * 3.0));
        let 一度目 = 写像.画面の画素とビュー空間の奥行きからセル添字を求める(画素の横, 画素の縦, 奥行き);
        let 二度目 = 写像.画面の画素とビュー空間の奥行きからセル添字を求める(画素の横, 画素の縦, 奥行き);
        assert_eq!(一度目, 二度目);
    }
}
