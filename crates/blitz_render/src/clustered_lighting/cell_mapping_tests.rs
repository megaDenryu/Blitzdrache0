//! セル添字への写像の全域性・全射性・決定性と、一次元の添字の往復の反証の検査。
//! 期待値は分割数と画素数から独立に組み立て、写像の実装を呼び戻さない。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::cell_index::クラスタ格子のセル添字;
use super::grid_division::クラスタ格子の分割数;
use super::narrowing::単精度へ狭める;
use super::test_fixture::{セル中央のビュー空間の位置, 検査用のクラスタ写像, 画面の幅, 画面の高さ};

/// 画面の外の画素も範囲の外の奥行きも端のセルへ入り、どの入力も格子の内側の1つのセルへ落ちる。
#[test]
fn どの画素と奥行きも格子の内側のセルへ落ちる() {
    let 写像 = 検査用のクラスタ写像();
    let 分割数 = 写像.分割数();
    let 奥行き一覧 = [-1.0e6, -1.0, 0.0, 1.0e-9, 0.05, 0.1, 1.0, 199.9, 200.0, 1.0e6, f32::NAN];
    for 画素の横 in [0, 1, 959, 960, 画面の幅 - 1, 画面の幅, 画面の幅 * 3] {
        for 画素の縦 in [0, 1, 539, 540, 画面の高さ - 1, 画面の高さ, 画面の高さ * 3] {
            for 奥行き in 奥行き一覧 {
                let 添字 =
                    写像.画面の画素とビュー空間の奥行きからセル添字を求める(画素の横, 画素の縦, メートル::生成する(奥行き));
                assert!(添字.横() < 分割数.横() && 添字.縦() < 分割数.縦() && 添字.奥行き() < 分割数.奥行き());
            }
        }
    }
}

/// どのセルにも、そこへ落ちる画素と奥行きが実在する。片方の端のセルへ全部が吸われる誤りをこれが落とす。
#[test]
fn どのセルにもそこへ落ちる入力が実在する() {
    let 写像 = 検査用のクラスタ写像();
    let 分割数 = 写像.分割数();
    for 一次元 in 0..分割数.セルの総数() {
        let 添字 = クラスタ格子のセル添字::一次元の添字から戻す(一次元, 分割数).unwrap();
        let 中央 = セル中央のビュー空間の位置(写像, 添字);
        let (画素の横, 画素の縦) = super::test_fixture::ビュー空間の位置が落ちる画素(中央);
        let 落ちたセル =
            写像.画面の画素とビュー空間の奥行きからセル添字を求める(画素の横, 画素の縦, メートル::生成する(-中央.z().値()));
        assert_eq!(落ちたセル, 添字, "セル{一次元}の中央が別のセルへ落ちた");
    }
}

#[test]
fn 同じ入力からは同じセル添字を返す() {
    let 写像 = 検査用のクラスタ写像();
    for 刻み in 0..=64u32 {
        let 画素の横 = 刻み * 29 % 画面の幅;
        let 画素の縦 = 刻み * 17 % 画面の高さ;
        let 奥行き = メートル::生成する(単精度へ狭める(0.1 + f64::from(刻み) * 3.0));
        let 一度目 = 写像.画面の画素とビュー空間の奥行きからセル添字を求める(画素の横, 画素の縦, 奥行き);
        let 二度目 = 写像.画面の画素とビュー空間の奥行きからセル添字を求める(画素の横, 画素の縦, 奥行き);
        assert_eq!(一度目, 二度目);
    }
}

#[test]
fn 一次元の添字は3軸の添字と往復する() {
    let 分割数 = クラスタ格子の分割数::仮置きの分割数を返す();
    for 一次元 in 0..分割数.セルの総数() {
        let 添字 = クラスタ格子のセル添字::一次元の添字から戻す(一次元, 分割数).unwrap();
        assert_eq!(添字.一次元の添字へ畳む(分割数), 一次元);
    }
}

#[test]
fn 格子の外のセル添字は作れない() {
    let 分割数 = クラスタ格子の分割数::仮置きの分割数を返す();
    assert!(クラスタ格子のセル添字::生成する(分割数.横(), 0, 0, 分割数).is_err());
    assert!(クラスタ格子のセル添字::生成する(0, 分割数.縦(), 0, 分割数).is_err());
    assert!(クラスタ格子のセル添字::生成する(0, 0, 分割数.奥行き(), 分割数).is_err());
    assert!(クラスタ格子のセル添字::一次元の添字から戻す(分割数.セルの総数(), 分割数).is_err());
}

#[test]
fn 分割数は各軸が1以上でなければ作れない() {
    assert!(クラスタ格子の分割数::生成する(0, 8, 24).is_err());
    assert!(クラスタ格子の分割数::生成する(16, 0, 24).is_err());
    assert!(クラスタ格子の分割数::生成する(16, 8, 0).is_err());
    assert_eq!(
        クラスタ格子の分割数::生成する(16, 8, 24).unwrap(),
        クラスタ格子の分割数::仮置きの分割数を返す()
    );
}
