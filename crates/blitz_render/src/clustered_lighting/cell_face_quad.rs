//! セルの錐台を作る6つの面を、平面の凸四角形として並べる工程。受け取るのは錐台、返すのは面ごとの四隅である。
//!
//! 錐台は8つの隅の凸包であり、境界はこの6つの四角形だけからなる。外にある点から錐台までの最短距離は
//! 6つの四角形までの距離の最小と等しいため、厳密な交差判定はこの並びの上で閉じる。
//!
//! 四隅を巡回の順で並べるのは、四角形の内側の判定が辺の向きの一致で決まるためである。順が巡回でないと、
//! 内側の判定が交差した四辺形の判定になり答えが変わる。
//!
//! 側面の四角形は台形である。奥行きが深いほど断面が線形に広がるためであり、平面であること
//! (側面が原点を通る平面`成分 = 傾き × 奥行き`に載ること)は変わらない。

use blitz_math::{ビュー, メートル, 位置};

use super::cell_frustum::クラスタ格子のセルの錐台;

/// 四角形1つの四隅。巡回の順に並ぶ。
pub(super) type 面の四隅 = [位置<ビュー>; 4];

pub(super) fn 六面を並べる(錐台: クラスタ格子のセルの錐台) -> [面の四隅; 6] {
    let 近 = 錐台.奥行きの区間().下限().値();
    let 遠 = 錐台.奥行きの区間().上限().値();
    let (横下, 横上) = (錐台.横の傾きの区間().下限(), 錐台.横の傾きの区間().上限());
    let (縦下, 縦上) = (錐台.縦の傾きの区間().下限(), 錐台.縦の傾きの区間().上限());
    let 隅 = |奥行き: f32, 横の傾き: f32, 縦の傾き: f32| 隅を作る(奥行き, 横の傾き, 縦の傾き);
    [
        [隅(近, 横下, 縦下), 隅(近, 横上, 縦下), 隅(近, 横上, 縦上), 隅(近, 横下, 縦上)],
        [隅(遠, 横下, 縦下), 隅(遠, 横上, 縦下), 隅(遠, 横上, 縦上), 隅(遠, 横下, 縦上)],
        [隅(近, 横下, 縦下), 隅(近, 横下, 縦上), 隅(遠, 横下, 縦上), 隅(遠, 横下, 縦下)],
        [隅(近, 横上, 縦下), 隅(近, 横上, 縦上), 隅(遠, 横上, 縦上), 隅(遠, 横上, 縦下)],
        [隅(近, 横下, 縦下), 隅(近, 横上, 縦下), 隅(遠, 横上, 縦下), 隅(遠, 横下, 縦下)],
        [隅(近, 横下, 縦上), 隅(近, 横上, 縦上), 隅(遠, 横上, 縦上), 隅(遠, 横下, 縦上)],
    ]
}

/// 奥行きと2つの傾きから隅のビュー空間の位置を作る。ビュー空間では視線が奥行きの負の向きであるため、
/// 奥行きの符号を反転した値がz成分になる。
fn 隅を作る(奥行き: f32, 横の傾き: f32, 縦の傾き: f32) -> 位置<ビュー> {
    位置::生成する(
        メートル::生成する(横の傾き * 奥行き),
        メートル::生成する(縦の傾き * 奥行き),
        メートル::生成する(-奥行き),
    )
}
