//! クラスタ格子の1つのセルが占めるビュー空間の錐台という形そのもの。触れる状態を持たず、担うのは
//! 錐台の表し方の保持と、位置が内側にあるかの判定である。
//!
//! 6つの平面の並びで持たず、奥行きの区間と傾きの区間で持つのは、側面の4つが原点を通り
//! `成分 = 傾き × 奥行き`という同じ形をしているためである。平面の係数を保存すると、傾きから毎回導ける値と
//! 保存された値の2つの表現ができ、食い違いうる。
//!
//! ビュー空間では視線が奥行きの負の向きであるため、奥行きはz成分の符号を反転した値である
//! (`crates/blitz_render/src/local_visibility/view_position.rs`の`カメラからの奥行き`が同じ規約を持つ)。

use blitz_math::{ビュー, メートル, 位置};

use super::interval::区間;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct クラスタ格子のセルの錐台 {
    奥行きの区間: 区間<メートル>,
    /// 横の傾きは`ビュー空間の横の成分 / カメラからの奥行き`である。
    横の傾きの区間: 区間<f32>,
    /// 縦の傾きは`ビュー空間の縦の成分 / カメラからの奥行き`である。
    縦の傾きの区間: 区間<f32>,
}

impl クラスタ格子のセルの錐台 {
    pub(super) fn 生成する(
        奥行きの区間: 区間<メートル>, 横の傾きの区間: 区間<f32>, 縦の傾きの区間: 区間<f32>
    ) -> Self {
        Self {
            奥行きの区間,
            横の傾きの区間,
            縦の傾きの区間,
        }
    }

    pub fn 奥行きの区間(self) -> 区間<メートル> {
        self.奥行きの区間
    }

    pub fn 横の傾きの区間(self) -> 区間<f32> {
        self.横の傾きの区間
    }

    pub fn 縦の傾きの区間(self) -> 区間<f32> {
        self.縦の傾きの区間
    }

    /// ビュー空間の位置がこの錐台の内側にあるか。境界の上は内側とみなす。
    pub fn 位置を含むか(self, 見る位置: 位置<ビュー>) -> bool {
        let 奥行き = メートル::生成する(-見る位置.z().値());
        if !self.奥行きの区間.含むか(奥行き) {
            return false;
        }
        傾きの区間に入るか(見る位置.x().値(), 奥行き.値(), self.横の傾きの区間)
            && 傾きの区間に入るか(見る位置.y().値(), 奥行き.値(), self.縦の傾きの区間)
    }
}

fn 傾きの区間に入るか(成分: f32, 奥行き: f32, 傾きの区間: 区間<f32>) -> bool {
    区間::生成する(傾きの区間.下限() * 奥行き, 傾きの区間.上限() * 奥行き).含むか(成分)
}
