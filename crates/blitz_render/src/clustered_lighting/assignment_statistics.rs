//! クラスタの選別が1フレームで作った割り当ての統計という量。触れる状態を持たず、担うのは数えた値の保持と、
//! そこから導ける割合の計算である。
//!
//! 「絞る」ことを1つの数で言えるようにするため、割り当ての総件数と、絞らなかった場合の件数
//! (セルの総数かける宣言した光の件数)の両方を持つ。前者だけでは格子の細かさが変わったときに大小を比べられない。
//!
//! 偽陽性を数に持つのは、保守的な交差判定が稜と角の近くで交わらない球を交わると答えるためである
//! (参照: `crates/blitz_render/src/clustered_lighting/sphere_intersection.rs`)。厳密な判定でも交わる件数を
//! 別に数えておけば、その差がそのまま余分に評価される光の件数になる。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct クラスタ選別の割り当て統計 {
    セルの総数: u32,
    宣言した光の件数: u32,
    光を1件以上持つセル数: u32,
    割り当ての総件数: u32,
    セルあたりの最大件数: u32,
    厳密にも交わる割り当て件数: u32,
}

impl クラスタ選別の割り当て統計 {
    pub(super) fn 生成する(
        セルの総数: u32,
        宣言した光の件数: u32,
        光を1件以上持つセル数: u32,
        割り当ての総件数: u32,
        セルあたりの最大件数: u32,
        厳密にも交わる割り当て件数: u32,
    ) -> Self {
        Self {
            セルの総数,
            宣言した光の件数,
            光を1件以上持つセル数,
            割り当ての総件数,
            セルあたりの最大件数,
            厳密にも交わる割り当て件数,
        }
    }

    pub fn セルの総数(self) -> u32 {
        self.セルの総数
    }

    pub fn 宣言した光の件数(self) -> u32 {
        self.宣言した光の件数
    }

    pub fn 光を1件以上持つセル数(self) -> u32 {
        self.光を1件以上持つセル数
    }

    pub fn 割り当ての総件数(self) -> u32 {
        self.割り当ての総件数
    }

    pub fn セルあたりの最大件数(self) -> u32 {
        self.セルあたりの最大件数
    }

    /// 1セルあたりの平均の割り当て件数。
    pub fn セルあたりの平均件数(self) -> f64 {
        if self.セルの総数 == 0 {
            return 0.0;
        }
        f64::from(self.割り当ての総件数) / f64::from(self.セルの総数)
    }

    /// 選別をしなかった場合の件数。全セルが全ての光を指す形である。
    pub fn 絞らなかった場合の総件数(self) -> u64 {
        u64::from(self.セルの総数) * u64::from(self.宣言した光の件数)
    }

    /// 絞らなかった場合に対する割り当ての総件数の比。小さいほど選別が絞っている。
    pub fn 絞りの比(self) -> f64 {
        let 分母 = f64::from(self.セルの総数) * f64::from(self.宣言した光の件数);
        if 分母 == 0.0 {
            return 0.0;
        }
        f64::from(self.割り当ての総件数) / 分母
    }

    /// 保守的な判定だけが交わると答えた割り当ての件数。そのセルで余分に評価される光の件数そのものである。
    pub fn 偽陽性の件数(self) -> u32 {
        self.割り当ての総件数.saturating_sub(self.厳密にも交わる割り当て件数)
    }

    /// 割り当ての総件数に対する偽陽性の割合。
    pub fn 偽陽性の率(self) -> f64 {
        if self.割り当ての総件数 == 0 {
            return 0.0;
        }
        f64::from(self.偽陽性の件数()) / f64::from(self.割り当ての総件数)
    }
}
