//! 球と錐台の交差判定のうち、一般の位置で偽陰性が1件も出ないことの反証の検査。期待値は判定の実装を1度も
//! 呼ばず、錐台の内側に並べた標本から球の中心までの距離で作る。錐台の面と角のすぐ外での判定は
//! `sphere_boundary_tests`が持つ。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, 位置};

use super::frustum_sampling::{向きへ離した位置, 錐台の標本から中心までの最短の距離};
use super::narrowing::単精度へ狭める;
use super::test_fixture::{
    セル中央のビュー空間の位置, 検査用のクラスタ写像, 検査用のセルの錐台, 検査用のセル添字を作る, 検査用の球を作る
};

/// 画面の四隅と中心、奥行きの手前と奥を混ぜたセル。傾きの大きい隅のセルを外すと、面までの距離を法線の
/// 長さで割り忘れた誤りが見えなくなる。
pub(super) const 検査するセル一覧: [(u32, u32, u32); 5] = [(0, 0, 0), (15, 7, 23), (15, 0, 18), (0, 7, 5), (8, 4, 12)];

#[test]
fn 錐台の中に中心がある球は交わると判定される() {
    let 写像 = 検査用のクラスタ写像();
    for (横, 縦, 奥行き) in 検査するセル一覧 {
        let 添字 = 検査用のセル添字を作る(横, 縦, 奥行き);
        let 中央 = セル中央のビュー空間の位置(写像, 添字);
        assert!(検査用のセルの錐台(写像, 添字).球と交わりうるか(検査用の球を作る(中央, 0.001)));
    }
}

#[test]
fn 半径より遠く離れた球は交わらないと判定される() {
    let 写像 = 検査用のクラスタ写像();
    let 錐台 = 検査用のセルの錐台(写像, 検査用のセル添字を作る(8, 4, 12));
    let 遠い中心 = 位置::生成する(メートル::生成する(500.0), メートル::生成する(-300.0), メートル::生成する(20.0));
    assert!(!錐台.球と交わりうるか(検査用の球を作る(遠い中心, 1.0)));
    assert!(錐台の標本から中心までの最短の距離(錐台, 遠い中心) > 1.0);
}

/// セルの視線の上に載りながら奥行きだけが離れた球は、近と遠の面の判定でだけ落ちる。横と縦の側面は通るため、
/// 奥行きの2面のどちらかを外した誤りをこれが落とす。
#[test]
fn 錐台より手前と奥にある球は交わらないと判定される() {
    let 写像 = 検査用のクラスタ写像();
    for (横, 縦, 奥行き) in 検査するセル一覧 {
        let 添字 = 検査用のセル添字を作る(横, 縦, 奥行き);
        let 錐台 = 検査用のセルの錐台(写像, 添字);
        let 中央 = セル中央のビュー空間の位置(写像, 添字);
        let 厚み = 錐台.奥行きの区間().上限().値() - 錐台.奥行きの区間().下限().値();
        let 半径 = 厚み * 0.1;
        for 奥行きの向き in [-1.0f32, 1.0] {
            let 中心 = 向きへ離した位置(中央, [0.0, 0.0, 奥行きの向き], 厚み);
            assert!(!錐台.球と交わりうるか(検査用の球を作る(中心, 半径)), "奥行きだけ離れた球を落とせなかった");
            assert!(錐台の標本から中心までの最短の距離(錐台, 中心) > 半径);
        }
    }
}

/// 錐台の内側の標本を1つでも覆う球は、必ず交わると判定されなければならない。偽陰性は光が消える絵の欠陥になる。
/// 半径とずらし幅をセルの奥行きの厚みに合わせるのは、セルの大きさが奥行きで2桁変わるためである。
#[test]
fn 錐台の内側の点を覆う球を交わらないと判定しない() {
    let 写像 = 検査用のクラスタ写像();
    for (横, 縦, 奥行き) in 検査するセル一覧 {
        let 添字 = 検査用のセル添字を作る(横, 縦, 奥行き);
        let 錐台 = 検査用のセルの錐台(写像, 添字);
        let 中央 = セル中央のビュー空間の位置(写像, 添字);
        let 厚み = 錐台.奥行きの区間().上限().値() - 錐台.奥行きの区間().下限().値();
        let 半径 = 厚み * 0.5;
        for 横の刻み in -2..=2i32 {
            for 縦の刻み in -2..=2i32 {
                for 奥の刻み in -2..=2i32 {
                    let ずらし = [横の刻み, 縦の刻み, 奥の刻み].map(|刻み| 単精度へ狭める(f64::from(刻み)) * 厚み * 0.4);
                    let 中心 = 向きへ離した位置(中央, ずらし, 1.0);
                    if 錐台の標本から中心までの最短の距離(錐台, 中心) <= 半径 {
                        assert!(
                            錐台.球と交わりうるか(検査用の球を作る(中心, 半径)),
                            "内側の点を覆う球を落とした: {中心:?}"
                        );
                    }
                }
            }
        }
    }
}
