//! セルの錐台を判定のときだけ広げる余裕の量。触れる状態を持たず、担うのは2つの余裕の値と、それぞれが
//! 何の食い違いを覆うかの記録である。
//!
//! 広げる向きが片方だけなのは、余分に広げた錐台がそのセルで光を1件余計に評価する費用にしかならないのに対し、
//! 狭いままの錐台は光が届く画素で光を落とし、絵の欠損になるためである(`sphere_intersection`が同じ理由で
//! 偽陽性の側へ倒している)。
//!
//! 奥行きの余裕が覆うのは、画素段が奥行きから段を決める式と、選別が段から奥行きの境界を戻す式が、どちらも
//! 単精度の対数と冪を踏むことによる往復の食い違いである。境界のすぐ上下では、画素段が段sを選んだ奥行きが
//! 選別の作った段sの区間からわずかに外へ出うる。値を1e-5にしたのは、Vulkanが対数・指数・冪へ許す誤差が
//! 最下位ビットの数十倍(相対でおよそ1e-6)であり、その1桁上を取ったためである。CPU正本との往復の実測は
//! `single_precision_agreement_tests`が見る。
//!
//! 横と縦の余裕が覆うのは、画素が面積を持つことと画素内ずらしである。画素の所属は中心で決まるが、その画素へ
//! 描かれた点は画素の中のどこにでも在り、ずらしを掛けた射影ではさらに半画素まで動く。タイルの境界に載った
//! 画素では、点の正規化装置座標がそのタイルの区間の外へ最大で1画素ぶん出る。
//! 参照: `_doc/設計/クラスタ多光源と点光源の影.md`

/// 奥行きの区間を上下へ広げる相対量。
pub const セルの奥行きを広げる相対量: f32 = 1.0e-5;

/// 横と縦の区間を広げる画素数。画素の面積(半画素)と画素内ずらし(半画素)の合計を覆う。
pub const セルの横と縦を広げる画素数: f32 = 1.0;
