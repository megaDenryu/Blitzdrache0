//! 1件の局所光が届く範囲を表すビュー空間の球という形そのもの。触れる状態を持たず、担うのは中心の全成分が
//! 有限であることの保証と、中心と半径を配ることである。
//!
//! 光の位置をビュー空間で持つのは、クラスタ格子が画面と奥行きで区切られており、セルの錐台がビュー空間の
//! 形だからである。ワールド位置のまま判定すると、セルごとに逆変換が要る。

use blitz_math::{ビュー, 位置};

use super::influence_radius::影響半径;
use super::input_error::クラスタ多光源入力エラー;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 局所光の影響範囲の球 {
    中心: 位置<ビュー>,
    半径: 影響半径,
}

impl 局所光の影響範囲の球 {
    pub fn 生成する(中心: 位置<ビュー>, 半径: 影響半径) -> Result<Self, クラスタ多光源入力エラー> {
        let 成分 = [中心.x().値(), 中心.y().値(), 中心.z().値()];
        if 成分.iter().any(|値| !値.is_finite()) {
            return Err(クラスタ多光源入力エラー::光の中心位置不正(成分));
        }
        Ok(Self { 中心, 半径 })
    }

    pub fn 中心(self) -> 位置<ビュー> {
        self.中心
    }

    pub fn 半径(self) -> 影響半径 {
        self.半径
    }
}
