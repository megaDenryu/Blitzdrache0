//! 局所光の影響範囲の球がセルの錐台と交わりうるかの判定。受け取るのは球、返すのは交わりうるかである。
//! 触れるのは錐台の奥行きの区間と傾きの区間の4つだけであり、格子も写像も知らない。
//!
//! 判定は錐台を作る6つの半空間それぞれについて「球の中心から面までの符号付き距離が半径以内か」を見る形である。
//! この形は**偽陰性を出さない**。交わる球は6つの半空間すべてから半径以内にあるためである。
//!
//! 注意: 交わらない球を交わると答えることはある。錐台の稜と角の近くで、6つの面すべてから半径以内でありながら
//! 錐台とは交わらない位置が存在するためである。この偽陽性は、そのセルで1件の光を余分に評価する費用として現れ、
//! 光の抜けにはならない。逆向きの誤り(偽陰性)は光が消える絵の欠陥になるため、費用の側へ倒している。

use super::cell_frustum::クラスタ格子のセルの錐台;
use super::interval::区間;
use super::light_sphere::局所光の影響範囲の球;

impl クラスタ格子のセルの錐台 {
    pub fn 球と交わりうるか(self, 球: 局所光の影響範囲の球) -> bool {
        let 中心 = 球.中心();
        let 半径 = 球.半径().長さ().値();
        let 奥行き = -中心.z().値();
        if self.奥行きの区間().下限().値() - 奥行き > 半径 || 奥行き - self.奥行きの区間().上限().値() > 半径 {
            return false;
        }
        側面の対から半径以内か(中心.x().値(), 中心.z().値(), self.横の傾きの区間(), 半径)
            && 側面の対から半径以内か(中心.y().値(), 中心.z().値(), self.縦の傾きの区間(), 半径)
    }
}

/// 1つの軸が作る2つの側面までの符号付き距離を見る。側面は原点を通り`成分 = 傾き × 奥行き`で表されるため、
/// 面の法線の長さは`sqrt(1 + 傾きの二乗)`であり、これで割ると符号付き距離になる。
fn 側面の対から半径以内か(成分: f32, z成分: f32, 傾きの区間: 区間<f32>, 半径: f32) -> bool {
    let (下限, 上限) = (傾きの区間.下限(), 傾きの区間.上限());
    let 下限の面までの距離 = (-下限 * z成分 - 成分) / (1.0 + 下限 * 下限).sqrt();
    let 上限の面までの距離 = (成分 + 上限 * z成分) / (1.0 + 上限 * 上限).sqrt();
    下限の面までの距離 <= 半径 && 上限の面までの距離 <= 半径
}
