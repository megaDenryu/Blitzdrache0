//! 下限と上限で挟まれた区間という形そのもの。触れる状態を持たず、担うのは下限が上限を超えないことの
//! 保証と、2つの端をそれぞれの名前で配ることである。
//!
//! 要素の型を型引数にするのは、クラスタ格子が奥行きの区間(メートル)と傾きの区間(無次元)と
//! 正規化装置座標の区間(無次元)の3つを同じ形で扱うためである。長さ2の配列で持つと、どちらの端が
//! 要素0かという約束が型の外側の申し送りになり、上下を取り違えても型検査を通る。

use std::fmt::Debug;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 区間<端> {
    下限: 端,
    上限: 端,
}

impl<端: PartialOrd + Copy + Debug> 区間<端> {
    /// 区間を作るのはこのモジュールの中だけであり、下限が上限を超える組はここでの取り違えでしか現れない。
    /// 非数の端も同じ扱いにするのは、非数を作れる入力を値オブジェクトの生成がすべて拒んでいるためである。
    pub(super) fn 生成する(下限: 端, 上限: 端) -> Self {
        assert!(下限 <= 上限, "区間の下限が上限を超えた: 下限{下限:?} 上限{上限:?}");
        Self { 下限, 上限 }
    }

    pub fn 下限(self) -> 端 {
        self.下限
    }

    pub fn 上限(self) -> 端 {
        self.上限
    }

    /// 両端を含む区間として判定する。
    pub fn 含むか(self, 値: 端) -> bool {
        self.下限 <= 値 && 値 <= self.上限
    }
}
