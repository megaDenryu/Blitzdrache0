//! 単精度の写しの反証が使う、検査する場所の作り方。受け取るのは無し、返すのは検査に使う奥行きの列と
//! 格子の条件である。判定は1つも持たない。
//!
//! 判定と分けるのは、この列の作り方(境界のすぐ上下を最下位ビットで作る)がそれ自体で1つの関心事であり、
//! 4つの判定すべてが同じ列を読むためである。

use blitz_math::メートル;

use super::depth_range::クラスタの奥行き範囲;
use super::single_precision_transcript::単精度で段の境界の奥行きを求める;

pub(super) const 近: f32 = 0.1;
pub(super) const 遠: f32 = 2000.0;
pub(super) const 奥行きの分割数: u32 = 24;
/// 横と縦それぞれの、画素数と分割数の組。仮置きの分割数と代表的な画面の寸法である。
pub(super) const 画素数と分割数の組一覧: [(u32, u32); 2] = [(1280, 16), (720, 8)];

pub(super) fn 奥行き範囲() -> クラスタの奥行き範囲 {
    クラスタの奥行き範囲::生成する(メートル::生成する(近), メートル::生成する(遠))
        .unwrap_or_else(|誤り| panic!("検査用の奥行き範囲を作れない: {誤り}"))
}

/// 段の境界のすぐ上下と、範囲を対数で等分した点を並べた検査用の奥行きの列。
pub(super) fn 検査する奥行き一覧() -> Vec<f32> {
    let mut 一覧 = Vec::new();
    for 番号 in 0..=奥行きの分割数 {
        let 境界 = 単精度で段の境界の奥行きを求める(番号, 近, 遠, 奥行きの分割数);
        for 段数 in 0..4 {
            一覧.push(値を最下位ビットぶん動かす(境界, -段数));
            一覧.push(値を最下位ビットぶん動かす(境界, 段数));
        }
    }
    for 番号 in 0..=2000u32 {
        一覧.push(近 * (遠 / 近).powf(等分の割合(番号)));
    }
    一覧.retain(|奥行き| (近..=遠).contains(奥行き));
    一覧
}

/// 単精度の刻みぶん値を前後へ動かす。境界のすぐ上下という場所を、機材に依らない形で作るために使う。
fn 値を最下位ビットぶん動かす(値: f32, 段数: i32) -> f32 {
    let mut 動いた = 値;
    for _ in 0..段数.abs() {
        動いた = if 段数 < 0 {
            f32::from_bits(動いた.to_bits().saturating_sub(1))
        } else {
            f32::from_bits(動いた.to_bits().saturating_add(1))
        };
    }
    動いた
}

fn 等分の割合(番号: u32) -> f32 {
    super::narrowing::単精度へ狭める(f64::from(番号) / 2000.0)
}

/// 画素の中心が当たる正規化装置座標。左端が-1、右端が+1である。
pub(super) fn 画素の中心の正規化装置座標(画素: u32, 画素数: u32) -> f32 {
    super::narrowing::単精度へ狭める(2.0 * (f64::from(画素) + 0.5) / f64::from(画素数) - 1.0)
}
