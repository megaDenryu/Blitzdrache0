//! 打ち切りの閾値という量そのもの。触れる状態を持たず、担うのは有限かつ正であることの保証である。
//!
//! 点光源の放射と同じ次元を持ち、色を掛ける前の大きさで比べる。世界を作る側が「この明るさまで落ちたら
//! 届いていないとみなす」という判断を数として置く場所であり、推奨の影響半径の導出だけがこれを消費する。
//! 参照: `_doc/設計/クラスタ多光源と点光源の影.md`

use super::input_error::クラスタ多光源入力エラー;

/// 放射がこの値まで落ちた距離を、光が届かなくなった距離とみなす基準。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 打ち切りの閾値(f32);

impl 打ち切りの閾値 {
    pub fn 生成する(値: f32) -> Result<Self, クラスタ多光源入力エラー> {
        if !値.is_finite() || 値 <= 0.0 {
            return Err(クラスタ多光源入力エラー::打ち切りの閾値不正(値));
        }
        Ok(Self(値))
    }

    pub fn 値(self) -> f32 {
        self.0
    }
}
