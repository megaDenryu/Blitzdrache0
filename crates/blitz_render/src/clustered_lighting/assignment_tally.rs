//! 割り当ての走査が途中で持つ4つの数。触れるのはその4つだけであり、走査の順も突き合わせの中身も知らない。
//!
//! 数を型へ閉じるのは、走査の側が「区間を1つ見たら3つの数を同時に進める」ことを守らなければならないためである。
//! 数を裸の変数で持つと、片方だけを進める書き方が通ってしまう。

use super::assignment_statistics::クラスタ選別の割り当て統計;
use super::cell_light_interval::セルの光の区間;

pub(super) struct 割り当ての数え {
    光を1件以上持つセル数: u32,
    割り当ての総件数: u32,
    セルあたりの最大件数: u32,
    厳密にも交わる割り当て件数: u32,
}

impl 割り当ての数え {
    pub(super) const fn 空で始める() -> Self {
        Self {
            光を1件以上持つセル数: 0,
            割り当ての総件数: 0,
            セルあたりの最大件数: 0,
            厳密にも交わる割り当て件数: 0,
        }
    }

    pub(super) fn 区間を数える(&mut self, 区間: セルの光の区間) {
        if 区間.件数() > 0 {
            self.光を1件以上持つセル数 += 1;
        }
        self.割り当ての総件数 += 区間.件数();
        self.セルあたりの最大件数 = self.セルあたりの最大件数.max(区間.件数());
    }

    pub(super) fn 厳密にも交わる1件を数える(&mut self) {
        self.厳密にも交わる割り当て件数 += 1;
    }

    pub(super) fn 統計へ写す(self, セルの総数: u32, 宣言した光の件数: u32) -> クラスタ選別の割り当て統計 {
        クラスタ選別の割り当て統計::生成する(
            セルの総数,
            宣言した光の件数,
            self.光を1件以上持つセル数,
            self.割り当ての総件数,
            self.セルあたりの最大件数,
            self.厳密にも交わる割り当て件数,
        )
    }
}
