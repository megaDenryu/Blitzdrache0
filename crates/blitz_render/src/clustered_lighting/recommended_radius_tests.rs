//! 推奨の影響半径の反証の検査。期待値は導出の式を呼び戻さず、逆二乗の定義へ半径を入れ直して閾値に
//! 戻るかを見る形で作る。導出の式をそのまま期待値に使うと、式を書き換えた誤りが検査を素通りする。

#![allow(clippy::unwrap_used)]

use crate::lighting_input::光強度;

use super::cutoff_threshold::打ち切りの閾値;
use super::narrowing::単精度へ狭める;
use super::point_light_radiance::距離の二乗へ足す微小量;
use super::recommended_radius::強度と打ち切りの閾値から推奨の影響半径を求める;

fn 推奨の半径(強度: f32, 閾値: f32) -> f32 {
    強度と打ち切りの閾値から推奨の影響半径を求める(光強度::生成する(強度).unwrap(), 打ち切りの閾値::生成する(閾値).unwrap())
        .unwrap()
        .長さ()
        .値()
}

/// 強度100・閾値0.01なら、微小量を無視した半径は10000の平方根で100メートルになる。
#[test]
fn 推奨の半径は手計算の値に一致する() {
    let 半径 = 推奨の半径(100.0, 0.01);
    assert!((半径 - 100.0).abs() < 1.0e-3, "推奨の半径が手計算と合わない: {半径}");
}

/// 窓を掛ける前の逆二乗へ推奨の半径を入れ直すと、打ち切りの閾値へ戻る。
#[test]
fn 推奨の半径では窓を掛ける前の放射が打ち切りの閾値に戻る() {
    for (強度, 閾値) in [(1.0, 0.001), (10.0, 0.01), (100.0, 0.05), (2500.0, 0.5)] {
        let 半径 = 推奨の半径(強度, 閾値);
        let 戻した放射 = 強度 / (半径 * 半径 + 距離の二乗へ足す微小量);
        let 相対誤差 = (戻した放射 - 閾値).abs() / 閾値;
        assert!(相対誤差 < 1.0e-4, "強度{強度}閾値{閾値}で放射が戻らない: {戻した放射}");
    }
}

#[test]
fn 強度が上がるほど推奨の半径は伸びる() {
    let mut 直前 = 推奨の半径(1.0, 0.01);
    for 倍率 in 2..=50u32 {
        let 半径 = 推奨の半径(単精度へ狭める(f64::from(倍率)), 0.01);
        assert!(半径 > 直前, "強度{倍率}で推奨の半径が縮んだ: {直前} から {半径}");
        直前 = 半径;
    }
}

/// 閾値に対して強度が小さすぎると正の半径が立たない。既定値を黙って入れず、失敗として返す。
#[test]
fn 強度が閾値に届かないときは推奨の半径を作れない() {
    let 結果 =
        強度と打ち切りの閾値から推奨の影響半径を求める(光強度::生成する(0.0).unwrap(), 打ち切りの閾値::生成する(1.0).unwrap());
    assert!(結果.is_err());
}

#[test]
fn 打ち切りの閾値は有限かつ正でなければ作れない() {
    assert!(打ち切りの閾値::生成する(0.0).is_err());
    assert!(打ち切りの閾値::生成する(-1.0).is_err());
    assert!(打ち切りの閾値::生成する(f32::INFINITY).is_err());
    assert!(打ち切りの閾値::生成する(f32::NAN).is_err());
}
