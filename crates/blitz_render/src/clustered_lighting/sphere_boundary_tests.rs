//! 球と錐台の交差判定のうち、錐台の面と角のすぐ外側という境界での反証の検査。面のすぐ外は必ず交わると
//! 判定されなければならず、角のすぐ外は交わらなくても交わると判定されうる。この2つで判定の倒し方
//! (偽陰性を出さず偽陽性は許す)が両側から挟まれる。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, 位置};

use super::frustum_sampling::{向きへ離した位置, 向きを長さ1へそろえる, 点と点の距離, 錐台の内側の標本を並べる};
use super::sphere_intersection_tests::検査するセル一覧;
use super::test_fixture::{検査用のクラスタ写像, 検査用のセル添字を作る, 検査用の球を作る};

/// 側面のすぐ外にある球は必ず交わると判定される。面までの距離を法線の長さで割らずに測ると、傾きの大きい
/// 側面ではこの距離が実際より`sqrt(1 + 傾きの二乗)`倍に見え、半径の内側にある球を落とす偽陰性になる。
#[test]
fn 側面から半径の内側にある球は交わると判定される() {
    let 写像 = 検査用のクラスタ写像();
    for (横, 縦, 奥行き) in 検査するセル一覧 {
        let 錐台 = 写像.セルの錐台を求める(検査用のセル添字を作る(横, 縦, 奥行き));
        let 傾きの上限 = 錐台.横の傾きの区間().上限();
        let 面の奥行き = (錐台.奥行きの区間().下限().値() + 錐台.奥行きの区間().上限().値()) * 0.5;
        let 面の縦の傾き = (錐台.縦の傾きの区間().下限() + 錐台.縦の傾きの区間().上限()) * 0.5;
        let 面の上の点 = 位置::生成する(
            メートル::生成する(傾きの上限 * 面の奥行き),
            メートル::生成する(面の縦の傾き * 面の奥行き),
            メートル::生成する(-面の奥行き),
        );
        let 半径 = (錐台.奥行きの区間().上限().値() - 錐台.奥行きの区間().下限().値()) * 0.25;
        let 中心 = 向きへ離した位置(面の上の点, 向きを長さ1へそろえる([1.0, 0.0, 傾きの上限]), 半径 * 0.9);
        assert!(
            錐台.球と交わりうるか(検査用の球を作る(中心, 半径)),
            "セル({横},{縦},{奥行き})の側面から半径の内側にある球を落とした"
        );
        assert!(
            錐台の内側の標本を並べる(錐台).into_iter().any(|標本| 点と点の距離(標本, 中心) <= 半径),
            "この球は錐台の内側の点を1つも覆っておらず、偽陰性の例になっていない"
        );
    }
}

/// 錐台の角の外にある球は、6つの面すべてから半径以内でありながら錐台とは交わらないことがある。
/// この偽陽性はそのセルで1件の光を余分に評価する費用にとどまり、光の抜けにはならない。
#[test]
fn 錐台の角をかすめる球は交わらなくても交わると判定される() {
    let 写像 = 検査用のクラスタ写像();
    let 錐台 = 写像.セルの錐台を求める(検査用のセル添字を作る(8, 4, 12));
    let 近 = 錐台.奥行きの区間().下限().値();
    let 横下限 = 錐台.横の傾きの区間().下限();
    let 縦下限 = 錐台.縦の傾きの区間().下限();
    let 外向きの和 = [
        [0.0, 0.0, 1.0],
        向きを長さ1へそろえる([-1.0, 0.0, -横下限]),
        向きを長さ1へそろえる([0.0, -1.0, -縦下限]),
    ]
    .iter()
    .fold([0.0f32; 3], |合計, 向き| [合計[0] + 向き[0], 合計[1] + 向き[1], 合計[2] + 向き[2]]);
    let 角 = 位置::生成する(メートル::生成する(横下限 * 近), メートル::生成する(縦下限 * 近), メートル::生成する(-近));
    let 中心 = 向きへ離した位置(角, 外向きの和, 0.01);
    let 半径 = 0.014;
    assert!(錐台.球と交わりうるか(検査用の球を作る(中心, 半径)), "角の外の球を面の判定が落とした");
    assert!(
        錐台の内側の標本を並べる(錐台).into_iter().all(|標本| 点と点の距離(標本, 中心) > 半径),
        "この球は錐台と実際に交わっており、偽陽性の例になっていない"
    );
}
