//! クラスタ格子が奥行きを刻む範囲という量。触れる状態を持たず、担うのは近と遠がともに有限かつ正で、
//! 近が遠より手前であることの保証である。
//!
//! ビュー空間のカメラからの奥行きで持つのは、この量が深度バッファの値の向き(逆Zかどうか)に依存しないためである。
//! 遠クリップを広げても分割式は変わらず、この範囲の値だけが変わる。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

use blitz_math::メートル;

use super::input_error::クラスタ多光源入力エラー;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct クラスタの奥行き範囲 {
    近: メートル,
    遠: メートル,
}

impl クラスタの奥行き範囲 {
    pub fn 生成する(近: メートル, 遠: メートル) -> Result<Self, クラスタ多光源入力エラー> {
        let 範囲外 = !近.値().is_finite() || 近.値() <= 0.0 || !遠.値().is_finite() || 遠.値() <= 近.値();
        if 範囲外 {
            return Err(クラスタ多光源入力エラー::奥行き範囲不正 {
                近: 近.値(), 遠: 遠.値()
            });
        }
        Ok(Self { 近, 遠 })
    }

    pub fn 近(self) -> メートル {
        self.近
    }

    pub fn 遠(self) -> メートル {
        self.遠
    }
}
