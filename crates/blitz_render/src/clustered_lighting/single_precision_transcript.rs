//! シェーダーが踏む単精度の式の写し。受け取るのは正本と同じ引数、返すのは単精度だけで組んだ答えである。
//! 触れる状態を持たず、担うのは「GPUがどう計算するか」をCPUの上で再現することだけである。
//!
//! 正本(`screen_tile`と`depth_slice`)と別に置くのは、正本が中間を倍精度で組んで最後に狭めるのに対し、
//! シェーダーは最初から最後まで単精度で踏むためである。2つの答えが分かれるのはセルの境界のすぐ上下だけであり、
//! その食い違いの大きさを測って余裕の量が足りていることを`single_precision_agreement_tests`が確かめる。
//!
//! 注意: この写しの相手は`shaders/cluster_mapping.slang`である。式を変えるときは両方を同時に変える。
//! 注意: 写しがGPUと完全に同じ答えを返す保証は無い。Vulkanは対数・指数・冪へ最下位ビットの数十倍の誤差を
//! 許すため、同じ式でも機材ごとに答えが分かれうる。この写しが見るのは式の形の一致であり、絵の欠損を防ぐのは
//! 余裕の量を掛けた錐台の側である(`cell_boundary_margin`)。

use crate::numeric::floor_index::実数位置の床の添字;

/// 単精度で組んだ、奥行きが属する段の添字。
pub fn 単精度で奥行きから段の添字を求める(奥行き: f32, 近: f32, 遠: f32, 分割数: u32) -> u32 {
    let 実数の段 = (奥行き / 近).ln() / (遠 / 近).ln() * 符号なし整数を単精度へ写す(分割数);
    実数位置の床の添字(f64::from(実数の段), 分割数 - 1)
}

/// 単精度で組んだ、段の境界の奥行き。境界の番号は0から分割数までを取る。
pub fn 単精度で段の境界の奥行きを求める(境界の番号: u32, 近: f32, 遠: f32, 分割数: u32) -> f32 {
    近 * (遠 / 近).powf(符号なし整数を単精度へ写す(境界の番号) / 符号なし整数を単精度へ写す(分割数))
}

/// 単精度で組んだ、画素が属するタイルの添字。整数だけで組むため正本と同じ答えを返す。
///
/// 注意: 積を32ビットで作る。シェーダーの符号なし整数が32ビットであり、64ビットの整数を要求しないためである。
/// 画素数は交換列が作れる寸法(2の14乗以下)、分割数は仮置きで16以下であるため、積は2の20乗を超えない。
pub fn 単精度の写しで画素からタイルの添字を求める(画素: u32, 画素数: u32, 分割数: u32) -> u32 {
    let 上限 = 分割数 - 1;
    let 画素の中心の二倍 = 2 * 画素 + 1;
    (画素の中心の二倍 * 分割数 / (2 * 画素数)).min(上限)
}

/// 単精度で組んだ、タイルが占める正規化装置座標の区間。左端が-1、右端が+1である。
pub fn 単精度でタイルの正規化装置座標の区間を求める(添字: u32, 分割数: u32) -> (f32, f32) {
    let タイルの幅 = 2.0 / 符号なし整数を単精度へ写す(分割数);
    let 下限 = 符号なし整数を単精度へ写す(添字) * タイルの幅 - 1.0;
    (下限, 下限 + タイルの幅)
}

/// 選別が判定に使う、余裕を掛けた段の奥行きの区間。手前の端の段は0まで、奥の端の段は無限まで伸ばす。
/// 端を伸ばすのは、近クリップの手前と遠クリップの奥に表面が無く、そこで区間を切っても得るものが無いためである。
pub fn 単精度で選別が使う段の奥行きの区間を求める(添字: u32, 近: f32, 遠: f32, 分割数: u32, 余裕: f32) -> (f32, f32) {
    let 下限 = if 添字 == 0 {
        0.0
    } else {
        単精度で段の境界の奥行きを求める(添字, 近, 遠, 分割数) * (1.0 - 余裕)
    };
    let 上限 = if 添字 + 1 >= 分割数 {
        f32::INFINITY
    } else {
        単精度で段の境界の奥行きを求める(添字 + 1, 近, 遠, 分割数) * (1.0 + 余裕)
    };
    (下限, 上限)
}

/// 選別が判定に使う、余裕を掛けたタイルの正規化装置座標の区間。余裕は画素数で受け、その軸の画素数で幅へ直す。
pub fn 単精度で選別が使うタイルの区間を求める(添字: u32, 分割数: u32, 画素数: u32, 余裕画素数: f32) -> (f32, f32) {
    let (下限, 上限) = 単精度でタイルの正規化装置座標の区間を求める(添字, 分割数);
    let 余裕 = 余裕画素数 * 2.0 / 符号なし整数を単精度へ写す(画素数);
    (下限 - 余裕, 上限 + 余裕)
}

/// 符号なし整数を単精度へ写す。2の24乗未満の値では丸めが起きないため、シェーダーの`float(x)`と同じ答えになる。
fn 符号なし整数を単精度へ写す(値: u32) -> f32 {
    super::narrowing::単精度へ狭める(f64::from(値))
}
