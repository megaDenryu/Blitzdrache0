//! クラスタ格子が画面と奥行きを何分割するかという量。触れる状態を持たず、担うのは各軸が1以上であることと
//! 積が符号なし32ビットに収まることの保証、および実測前の仮置きの値を1箇所で持つことである。
//!
//! 仮置きの値を定数として1箇所へ置くのは、画素段と選別のコンピュートの両方が同じ値を読む必要があり、
//! 2箇所へ別々に定数を置くと片方だけを直した食い違いが絵にしか出ないためである
//! (`crates/blitz_render/src/vulkan/lighting_query/capacity.rs`が容量の定数で同じ形を採っている)。
//! 参照: `_doc/設計/クラスタ多光源と点光源の影.md`

use super::input_error::クラスタ多光源入力エラー;

/// 画面の横のタイル数。実測で調整するまでの仮置きである。
const 仮置きの横の分割数: u32 = 16;
/// 画面の縦のタイル数。実測で調整するまでの仮置きである。
const 仮置きの縦の分割数: u32 = 8;
/// 奥行きの段の数。実測で調整するまでの仮置きである。
const 仮置きの奥行きの分割数: u32 = 24;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct クラスタ格子の分割数 {
    横: u32,
    縦: u32,
    奥行き: u32,
}

impl クラスタ格子の分割数 {
    pub fn 生成する(横: u32, 縦: u32, 奥行き: u32) -> Result<Self, クラスタ多光源入力エラー> {
        let 総数 = 横.checked_mul(縦).and_then(|積| 積.checked_mul(奥行き));
        match 総数 {
            Some(総数) if 総数 > 0 => Ok(Self { 横, 縦, 奥行き }),
            _ => Err(クラスタ多光源入力エラー::分割数不正 { 横, 縦, 奥行き }),
        }
    }

    /// 実測で調整するまでの仮置きの分割数。
    pub fn 仮置きの分割数を返す() -> Self {
        Self {
            横: 仮置きの横の分割数,
            縦: 仮置きの縦の分割数,
            奥行き: 仮置きの奥行きの分割数,
        }
    }

    pub fn 横(self) -> u32 {
        self.横
    }

    pub fn 縦(self) -> u32 {
        self.縦
    }

    pub fn 奥行き(self) -> u32 {
        self.奥行き
    }

    /// 格子が持つセルの総数。生成が積の収まりを確かめているため、この掛け算は溢れない。
    pub fn セルの総数(self) -> u32 {
        self.横 * self.縦 * self.奥行き
    }
}
