//! GPUメモリ確保の役割の分類。触れる状態を持たず、担うのは分類の並びと、その並びから配列の添字を引くことだけである。
//!
//! 統計の型から分けるのは、分類を1つ増やすときに触るのがこのファイルだけになるようにするためである。
//! 並びと添字が別々の場所にあると、片方だけを足したときに用途別の配列が1つずれる。
//!
//! `点光源の影の立方体配列`を描画画像から分けて数えるのは、この1枚だけが灯の件数と面の一辺から常駐量を予測できる資源であり、
//! 予測と実際の確保量を突き合わせるためである(参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断l」)。

/// GPUメモリ確保を、確保した資源の役割で分類する。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum GPUメモリ用途 {
    デバイスバッファ,
    ホストバッファ,
    描画画像,
    テクスチャ画像,
    読み戻しバッファ,
    点光源の影の立方体配列, // 描画画像から分けて数える
}

impl GPUメモリ用途 {
    pub(crate) const 一覧: [Self; 6] = [
        Self::デバイスバッファ,
        Self::ホストバッファ,
        Self::描画画像,
        Self::テクスチャ画像,
        Self::読み戻しバッファ,
        Self::点光源の影の立方体配列,
    ];

    pub fn 名称(self) -> &'static str {
        match self {
            Self::デバイスバッファ => "デバイスバッファ",
            Self::ホストバッファ => "ホストバッファ",
            Self::描画画像 => "描画画像",
            Self::テクスチャ画像 => "テクスチャ画像",
            Self::読み戻しバッファ => "読み戻しバッファ",
            Self::点光源の影の立方体配列 => "点光源の影の立方体配列",
        }
    }

    pub(crate) fn 添字(self) -> usize {
        match self {
            Self::デバイスバッファ => 0,
            Self::ホストバッファ => 1,
            Self::描画画像 => 2,
            Self::テクスチャ画像 => 3,
            Self::読み戻しバッファ => 4,
            Self::点光源の影の立方体配列 => 5,
        }
    }
}
