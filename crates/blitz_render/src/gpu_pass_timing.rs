//! パス1つぶんのGPU時間の分布。担当するのは、直近の窓から求めた平均・中央値・95パーセンタイルと標本数を
//! 1つの値として運ぶことである。触れる値は4つだけで、生成できるのは計測の側だけである。
//!
//! 平均と分位を一緒に持つのは、報告と判定で使う量が違うためである。既存の時系列は平均で並んでおり、
//! 条件どうしの比較は跳ねた標本に強い中央値と95パーセンタイルで行う
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」)。
//!
//! 窓へ入る前の生の値は`frame_sample`が運ぶ。集約から元の列は復元できないため、分位を独立に計算し直す検収はそちらを読む。

mod frame_sample;

pub use frame_sample::フレーム別の標本;

/// 分布を求める窓が保つ標本の数。この数が、報告の分位が「直近の何フレームから採った値か」を決める。
/// 実装(`vulkan::gpu_timing::pass_time_window`)がこの定数を読むため、窓の長さの正本はここ1箇所である。
pub const 窓の標本数: usize = 60;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct パス時間の分布 {
    平均ミリ秒: f64,
    中央値ミリ秒: f64,
    p95ミリ秒: f64,
    標本数: usize,
}

impl パス時間の分布 {
    pub(crate) fn 生成する(平均ミリ秒: f64, 中央値ミリ秒: f64, p95ミリ秒: f64, 標本数: usize) -> Self {
        Self {
            平均ミリ秒,
            中央値ミリ秒,
            p95ミリ秒,
            標本数,
        }
    }

    pub fn 平均ミリ秒(self) -> f64 {
        self.平均ミリ秒
    }

    pub fn 中央値ミリ秒(self) -> f64 {
        self.中央値ミリ秒
    }

    pub fn p95ミリ秒(self) -> f64 {
        self.p95ミリ秒
    }

    pub fn 標本数(self) -> usize {
        self.標本数
    }

    /// 距離区分ごとの分布を足し合わせた値。**中央値とp95は和の分位ではなく分位の和である**
    /// (フレームごとの合計を持たないため和の分位は求められない)。予算と突き合わせる目安として使う。
    pub fn 足し合わせる(self, 他: Self) -> Self {
        Self {
            平均ミリ秒: self.平均ミリ秒 + 他.平均ミリ秒,
            中央値ミリ秒: self.中央値ミリ秒 + 他.中央値ミリ秒,
            p95ミリ秒: self.p95ミリ秒 + 他.p95ミリ秒,
            標本数: self.標本数.min(他.標本数),
        }
    }
}
