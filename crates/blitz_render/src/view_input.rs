//! 1フレーム内の非空な視点一覧と、各視点のカメラ入力。
//! 注意: `ビュー射影`はカメラ相対フレーム(視点を原点に置き回転だけを持つビュー)で組み立てて渡す。
//! 対象側もカメラ大域原点を引いた位置を渡すため、ここへ大域の平行移動を入れると二重減算になる。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「カメラ相対描画の契約」

#[cfg(test)]
mod view_input_tests;

use blitz_math::{クリップ, ワールド, 変換, 大域ワールド位置};

#[derive(Debug, Clone)]
pub struct 描画視点 {
    ビュー射影: 変換<ワールド, クリップ>,
    カメラ大域位置: 大域ワールド位置,
    カメラ大域原点: 大域ワールド位置,
}

impl 描画視点 {
    pub fn 生成する(
        ビュー射影: 変換<ワールド, クリップ>, カメラ大域位置: 大域ワールド位置, カメラ大域原点: 大域ワールド位置
    ) -> Self {
        Self {
            ビュー射影,
            カメラ大域位置,
            カメラ大域原点,
        }
    }

    pub(crate) fn ビュー射影(&self) -> 変換<ワールド, クリップ> {
        self.ビュー射影
    }

    /// PBRの視線ベクトルに使う。相対化はフレームUBOの書き込みが行う。
    pub(crate) fn カメラ大域位置(&self) -> 大域ワールド位置 {
        self.カメラ大域位置
    }

    pub fn カメラ大域原点(&self) -> 大域ワールド位置 {
        self.カメラ大域原点
    }
}

#[derive(Debug, Clone)]
pub struct 描画視点一覧 {
    先頭: 描画視点,
    残り: Vec<描画視点>,
}

impl 描画視点一覧 {
    pub fn 生成する(先頭: 描画視点, 残り: Vec<描画視点>) -> Self {
        Self { 先頭, 残り }
    }

    pub fn 視点数(&self) -> usize {
        self.残り.len() + 1
    }

    pub(crate) fn 先頭(&self) -> &描画視点 {
        &self.先頭
    }
}
