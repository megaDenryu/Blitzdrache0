//! 1フレーム内の非空な視点一覧と、各視点のカメラ入力。
//! 注意: `ビュー射影の組`の3本はすべてカメラ相対フレーム(視点を原点に置き回転だけを持つビュー)で組み立てて渡す。
//! 対象側もカメラ大域原点を引いた位置を渡すため、ここへ大域の平行移動を入れると二重減算になる。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「カメラ相対描画の契約」

mod view_projections;

#[cfg(test)]
mod view_input_tests;

use blitz_math::{ビュー, ワールド, 変換, 大域ワールド位置};

pub use view_projections::ビュー射影の組;

use crate::local_visibility::射影の復元;

/// 1つの視点のカメラ入力。`カメラ相対ビュー変換`はクラスタの選別が局所光の位置をビュー空間へ写すために読む。
/// ビュー射影から取り出さずに視点が運ぶのは、取り出しが投影の作り方(視野角・逆Zの有無)へ暗黙に依存するためである。
/// `射影の復元`は同じ視点のビュー射影を組み立てた透視投影の量であり、深度から画素のビュー空間の位置を戻す工程が
/// 読む。行列から取り出さずに視点が運ぶのは、行列の一般の逆を必要としないことと、近クリップが正で遠より手前と
/// いった不変条件を型が守れることによる。
#[derive(Debug, Clone)]
pub struct 描画視点 {
    ビュー射影の組: ビュー射影の組,
    カメラ相対ビュー変換: 変換<ワールド, ビュー>, // カメラ相対ワールドからビュー空間へ写す変換
    カメラ大域位置: 大域ワールド位置,
    カメラ大域原点: 大域ワールド位置,
    射影の復元: 射影の復元, // 透視投影の4つの量と、ずらし付きが受けた画素内ずらし
}

impl 描画視点 {
    pub fn 生成する(
        ビュー射影の組: ビュー射影の組,
        カメラ相対ビュー変換: 変換<ワールド, ビュー>,
        カメラ大域位置: 大域ワールド位置,
        カメラ大域原点: 大域ワールド位置,
        射影の復元: 射影の復元,
    ) -> Self {
        Self {
            ビュー射影の組,
            カメラ相対ビュー変換,
            カメラ大域位置,
            カメラ大域原点,
            射影の復元,
        }
    }

    /// クラスタの選別が読む、カメラ相対ワールドからビュー空間への変換。
    pub(crate) fn カメラ相対ビュー変換(&self) -> 変換<ワールド, ビュー> {
        self.カメラ相対ビュー変換
    }

    /// 局所可視性補正の2つのコンピュートが押し込む射影の4つの量。
    pub(crate) fn 射影の復元(&self) -> 射影の復元 {
        self.射影の復元
    }

    /// どの用途がどの1本を読むかは`ビュー射影の組`が名前で決める。ここは組をそのまま渡すだけである。
    pub(crate) fn ビュー射影の組(&self) -> ビュー射影の組 {
        self.ビュー射影の組
    }

    /// PBRの視線ベクトルに使う。相対化はフレームUBOの書き込みが行う。
    pub(crate) fn カメラ大域位置(&self) -> 大域ワールド位置 {
        self.カメラ大域位置
    }

    pub fn カメラ大域原点(&self) -> 大域ワールド位置 {
        self.カメラ大域原点
    }
}

#[derive(Debug, Clone)]
pub struct 描画視点一覧 {
    先頭: 描画視点,
    残り: Vec<描画視点>,
}

impl 描画視点一覧 {
    pub fn 生成する(先頭: 描画視点, 残り: Vec<描画視点>) -> Self {
        Self { 先頭, 残り }
    }

    pub fn 視点数(&self) -> usize {
        self.残り.len() + 1
    }

    pub(crate) fn 先頭(&self) -> &描画視点 {
        &self.先頭
    }
}
