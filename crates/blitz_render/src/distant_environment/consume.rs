//! 遠方環境から焼いた派生表現を標準PBRが消費する式の正本。担うのは「拡散照度と鏡面畳込みと反射率積分表の
//! 3つの値から、表面が返す間接光の色を決める」ことだけであり、Vulkanの資源も画像の参照方法も知らない。
//!
//! CPU側に正本を置くのは、消費式が拡散と鏡面でエネルギーを分け合う関係を持ち、その関係をGPUを起動せずに
//! 検査できるようにするためである。金属で拡散が0になること、粗さが上がるほど参照する縮小段が奥へ動くことは
//! どちらも数の性質であり、絵を描かずに反証できる。シェーダーはこの式の写しである。
//!
//! 内側は3つに分かれる。反射率(垂直入射の反射率と粗さ対応のフレネル)、拡散(エネルギーの取り分と拡散の色)、
//! 鏡面(分割和の第2項の適用と粗さから縮小段の位置)であり、拡散と鏡面はどちらも反射率へ依存する。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」

