//! 遠方環境と3つの派生表現を焼くコンピュートシェーダーの束。
//!
//! 4本を1つの束にするのは、焼く順序と依存がこの4本の間で決まっており、一部だけを差し替えられる状態を
//! 作らないためである。大気のベイク済み画像の束と別に持つのは、遠方環境が大気の表ではなく、その上に置いた
//! 供給から作る間接照明の表現だからである。

use crate::compute_shader::コンピュートシェーダー;

/// 照明問い合わせ契約が遠方環境の枝のときだけパイプラインが作られる4本。
#[derive(Debug, Clone)]
pub struct 遠方環境のシェーダー一式 {
    pub 遠方環境: コンピュートシェーダー,
    pub 拡散照度: コンピュートシェーダー,
    pub 鏡面畳込み: コンピュートシェーダー,
    pub 反射率積分表: コンピュートシェーダー,
}
