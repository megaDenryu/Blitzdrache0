//! 遠方環境のGPU読み戻し検査の公開入口。担当するのは「ウィンドウを持たないGPUで大気のベイク済み画像を焼き、
//! その上で遠方環境の立方体画像を焼いて、中身を生の4成分で返す」ことである。
//! 呼び出し元は検収コマンドだけであり、本番の描画経路はここを通らない。
//!
//! 検証済みの値オブジェクトでなく生の4成分を返すのは、検査が非有限値や負の値を観測できなければならないためである。
//! 検証済みの型で返すと、まさに検査したい壊れた値が構築の時点で弾かれ、GPU側の欠陥が見えなくなる。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「検収(機械判定)」

use crate::atmosphere::{
    スカイビュー観測条件, 大気のベイク済み画像の解像度, 大気散乱媒体, 天空放射輝度の尺度, 空中遠近観測条件, 遠方環境の解像度
};
use crate::compute_shader::コンピュートシェーダー;
use crate::error::レンダラーエラー;
use crate::shader_bundle::大気のベイク済み画像のシェーダー一式;
use crate::validation_counter::検証層の状況;
use crate::vulkan::distant_environment;

/// 焼く条件一式。引数の列が伸び続けるのを避けて1つに束ねる。
pub struct 遠方環境の焼き上げ条件<'a> {
    pub 媒体: &'a 大気散乱媒体,
    pub 大気の解像度: 大気のベイク済み画像の解像度,
    pub スカイビュー条件: スカイビュー観測条件,
    pub 空中遠近条件: 空中遠近観測条件, // 焼かないが、大気の1フレーム入力が要求するため受け取る
    pub 遠方環境の解像度: 遠方環境の解像度,
    pub 尺度: 天空放射輝度の尺度,
    pub 大気のシェーダー: &'a 大気のベイク済み画像のシェーダー一式,
    pub 遠方環境のシェーダー: &'a コンピュートシェーダー,
}

/// GPUが焼いた遠方環境の中身と、その実行のvalidationの観測。
/// 並びは面(層番号の順)が最も外、次に縦、横が最も速く、CPU正本の`遠方環境を焼く`が返す並びと一致する。
/// 4成分目はシェーダーが予約として0を書くため、読む側はRGBの3成分だけを見る。
pub struct 遠方環境の読み戻し {
    テクセル一覧: Vec<[f32; 4]>,
    検証層の状況: 検証層の状況,
    検証件数: u64,
}

impl 遠方環境の読み戻し {
    pub fn テクセル一覧(&self) -> &[[f32; 4]] {
        &self.テクセル一覧
    }

    /// validation層を有効にできたかどうか。件数0が保証になるのは有効だった実行だけである。
    pub fn 検証層の状況(&self) -> 検証層の状況 {
        self.検証層の状況
    }

    pub fn 検証件数(&self) -> u64 {
        self.検証件数
    }
}

/// ウィンドウもスワップチェーンも作らずにGPUを初期化し、本番と同じパス宣言で遠方環境を焼いて読み戻す。
/// 送信は1回で、戻った時点でGPUの作業は完了している。
pub fn 遠方環境をgpuで焼いて読み戻す(
    条件: 遠方環境の焼き上げ条件<'_>
) -> Result<遠方環境の読み戻し, レンダラーエラー> {
    let 即時定数 = distant_environment::遠方環境の即時定数 {
        観測半径: 条件.スカイビュー条件.観測半径(条件.媒体.消散()).値(),
        太陽天頂余弦: 条件.スカイビュー条件.太陽天頂余弦().値(),
        太陽放射照度: 条件.尺度.太陽放射照度(),
        夜空放射輝度: 条件.尺度.夜空放射輝度(),
    };
    let (読み戻し, 検証) = distant_environment::遠方環境をgpuで焼いて読み戻す(distant_environment::遠方環境を焼く条件 {
        媒体: 条件.媒体,
        大気の解像度: 条件.大気の解像度,
        スカイビュー条件: 条件.スカイビュー条件,
        空中遠近条件: 条件.空中遠近条件,
        遠方環境の解像度: 条件.遠方環境の解像度,
        即時定数,
        大気のシェーダー: 条件.大気のシェーダー,
        遠方環境のシェーダー: 条件.遠方環境のシェーダー,
    })?;
    Ok(遠方環境の読み戻し {
        テクセル一覧: 読み戻し.テクセル一覧,
        検証層の状況: 検証.状況,
        検証件数: 検証.件数,
    })
}
