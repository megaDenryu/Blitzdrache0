//! 検収が派生表現の3つの画像へ直に与える解析入力。担うのは「拡散照度・鏡面畳込み・反射率積分表がどの値で
//! 埋まるか」を宣言することだけであり、Vulkanの資源もバイト並びも知らない。
//!
//! 大気から焼いた空を唯一のオラクルにしないのは、消費式の欠陥の所在を分離できないためである。焼いた空を
//! 使うと、垂直入射の反射率・反射率積分表の2成分・立方体の補間がすべて混ざった1つの数だけが出る。
//! 拡散だけ・鏡面の段だけ・鏡面の面だけを独立に立てれば、束縛と式と段と向きのどれが壊れたかが分かれる
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」)。
//!
//! 鏡面畳込みを判別共用体にするのは、段を見分ける判定と面を見分ける判定が別の埋め方を要るためである。
//! 1つの構造体に両方の色を持たせると、どちらの意味で埋めたのかが値からは決まらない。

use super::analytic_input_error::遠方環境の解析入力エラー;

/// 鏡面畳込みの立方体画像をどう埋めるか。
#[derive(Debug, Clone, PartialEq)]
pub enum 鏡面畳込みの解析入力 {
    /// 縮小段ごとに違う一様な色。粗さが正しい段を選んでいるかを判定する。並びは段番号の昇順である。
    段ごとの一様な色(Vec<[f32; 3]>),
    /// 立方体の面ごとに違う一様な色。全段が同じ埋め方をする。参照する向きが正しい面を選んでいるかを判定する。
    /// 並びは層番号の昇順であり、`立方体の面`の並びと同じである。
    面ごとの一様な色([[f32; 3]; 6]),
}

/// 3つの画像へ与える値の組。
#[derive(Debug, Clone, PartialEq)]
pub struct 遠方環境の解析入力 {
    拡散照度: [f32; 3],
    鏡面畳込み: 鏡面畳込みの解析入力,
    反射率積分表: [f32; 2],
}

impl 遠方環境の解析入力 {
    pub fn 生成する(
        拡散照度: [f32; 3],
        鏡面畳込み: 鏡面畳込みの解析入力,
        反射率積分表: [f32; 2],
    ) -> Result<Self, 遠方環境の解析入力エラー> {
        let 妥当 = 有限で非負か(&拡散照度) && 有限で非負か(&反射率積分表) && 鏡面畳込みが妥当か(&鏡面畳込み);
        if !妥当 {
            return Err(遠方環境の解析入力エラー::値域外);
        }
        Ok(Self {
            拡散照度,
            鏡面畳込み,
            反射率積分表,
        })
    }

    /// 拡散照度の立方体画像を埋める一様な照度。Lambertの畳み込み後の照度そのものであり、円周率で割るのは消費側である。
    pub fn 拡散照度(&self) -> [f32; 3] {
        self.拡散照度
    }

    pub fn 鏡面畳込み(&self) -> &鏡面畳込みの解析入力 {
        &self.鏡面畳込み
    }

    /// 反射率積分表の全テクセルへ書く2成分。第1成分が垂直入射の反射率に掛かる倍率、第2成分が足す量である。
    pub fn 反射率積分表(&self) -> [f32; 2] {
        self.反射率積分表
    }

    /// 焼いた鏡面畳込みの粗さ段数と噛み合うかを確かめる。段ごとの色を与えたのに段数が食い違うと、
    /// 判定が読む段と埋めた段がずれたまま通る。
    pub fn 粗さ段数と噛み合うか(&self, 粗さ段数: u32) -> Result<(), 遠方環境の解析入力エラー> {
        let 鏡面畳込みの解析入力::段ごとの一様な色(色一覧) = &self.鏡面畳込み else {
            return Ok(());
        };
        let 求める = usize::try_from(粗さ段数).unwrap_or(usize::MAX);
        if 色一覧.len() == 求める {
            return Ok(());
        }
        Err(遠方環境の解析入力エラー::段数不一致 {
            求める: 粗さ段数,
            与えた: 色一覧.len(),
        })
    }
}

fn 鏡面畳込みが妥当か(鏡面畳込み: &鏡面畳込みの解析入力) -> bool {
    match 鏡面畳込み {
        鏡面畳込みの解析入力::段ごとの一様な色(色一覧) => !色一覧.is_empty() && 色一覧.iter().all(|色| 有限で非負か(色)),
        鏡面畳込みの解析入力::面ごとの一様な色(色一覧) => 色一覧.iter().all(|色| 有限で非負か(色)),
    }
}

fn 有限で非負か(値: &[f32]) -> bool {
    値.iter().all(|成分| 成分.is_finite() && *成分 >= 0.0)
}
