//! 検収が畳み込みへ与える遠方環境の内容を組む工程。受け取るのは1面の一辺、返すのは定数の環境または
//! 方向性の強い環境である。
//!
//! 大気から焼いた遠方環境でなくここで組んだ環境を検収へ使うのは、畳み込みの正しさを解析解と突き合わせるためである。
//! 定数の環境なら拡散照度は円周率×放射輝度、鏡面畳込みはどの粗さ段も放射輝度そのものになる。大気から焼いた環境には
//! 閉じた形の答えが無く、GPUとCPUが同じ誤りを犯していても一致してしまう。
//!
//! 方向性の強い環境を余弦のべき乗で作るのは、向きについて滑らかでありながら1つの向きへ寄っているためである。
//! 滑らかさが面境界の連続性の判定を意味あるものにし、寄りが粗さを上げたときの分散の減りを見えるようにする。

use super::cube_side::立方体画像の一辺;
use super::environment_content::遠方環境の内容;
use super::error::派生表現エラー;
use crate::atmosphere::{テクセル中心の面内位置, 立方体の全面, 面と面内位置から向きを求める};

/// 方向性の強い環境が全方向へ持つ下限の放射輝度。成分ごとに違えるのは、赤と青を取り違える写しの誤りを
/// 判定に出すためである。
const 一様な下限: [f64; 3] = [0.05, 0.08, 0.12];

/// 方向性の強い環境の山の高さ。下限の数十倍を取り、粗さを上げたときの分散の減りが数値に出る差を作る。
const 山の高さ: [f64; 3] = [4.0, 3.0, 2.0];

/// 山の向き。どの面の軸とも一致しない向きを選ぶのは、面と向きの写像の誤りが面ごとの明るさの入れ替わりとして
/// 現れるようにするためである。
const 山の向き: [f64; 3] = [0.3, 0.8, 0.5];

/// 山の鋭さ。8乗は向きについて滑らかでありながら、半球のごく一部へ光が寄る形を作る。
const 山の鋭さ: i32 = 8;

pub fn 定数の遠方環境(一辺: 立方体画像の一辺, 放射輝度: [f64; 3]) -> Result<遠方環境の内容, 派生表現エラー> {
    遠方環境の内容::生成する(一辺, vec![放射輝度; 一辺.全テクセル数()])
}

pub fn 方向性の強い遠方環境(一辺: 立方体画像の一辺) -> Result<遠方環境の内容, 派生表現エラー> {
    let 単位の山の向き = 単位化した山の向き();
    let mut テクセル一覧 = Vec::with_capacity(一辺.全テクセル数());
    for 面 in 立方体の全面 {
        for 縦 in 0..一辺.値() {
            for 横 in 0..一辺.値() {
                let 向き =
                    面と面内位置から向きを求める(面, テクセル中心の面内位置(横, 一辺.値()), テクセル中心の面内位置(縦, 一辺.値()));
                テクセル一覧.push(山の値(向き, 単位の山の向き));
            }
        }
    }
    遠方環境の内容::生成する(一辺, テクセル一覧)
}

/// 山の向きを長さ1へ揃える。定数の3成分はどれも0でないため、長さは必ず正である。
fn 単位化した山の向き() -> [f64; 3] {
    let 長さ = (山の向き[0] * 山の向き[0] + 山の向き[1] * 山の向き[1] + 山の向き[2] * 山の向き[2]).sqrt();
    [山の向き[0] / 長さ, 山の向き[1] / 長さ, 山の向き[2] / 長さ]
}

fn 山の値(向き: [f64; 3], 単位の山の向き: [f64; 3]) -> [f64; 3] {
    let 余弦 = (向き[0] * 単位の山の向き[0] + 向き[1] * 単位の山の向き[1] + 向き[2] * 単位の山の向き[2]).max(0.0);
    let 山 = 余弦.powi(山の鋭さ);
    [
        一様な下限[0] + 山の高さ[0] * 山,
        一様な下限[1] + 山の高さ[1] * 山,
        一様な下限[2] + 山の高さ[2] * 山,
    ]
}
