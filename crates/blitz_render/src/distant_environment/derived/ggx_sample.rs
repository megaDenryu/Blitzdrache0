//! GGXの法線分布から半ベクトルを1本標本する工程。受け取るのは単位正方形の標本と粗さと法線、
//! 返すのは法線のまわりに分布した単位ベクトルである。
//!
//! 一様に標本して分布で重み付けるのでなく分布そのものから標本するのは、粗さが小さいほど分布が鋭くなり、
//! 一様標本ではほとんどの標本が0に近い重みしか持たなくなるためである。この標本の取り方では、
//! 分布の重みが標本の密度に吸収されて重みが消える。
//!
//! 鏡面の畳み込みとBRDF積分表の両方がこの1つの標本を使う。2つが別々の標本を持つと、
//! 分割和の2つの項が別の分布を前提にした値になる。
//! 注意: この標本は`shaders/ggx_sample.slang`の写しを持つ。ここが正本である。

use super::roughness::粗さ;
use super::spherical_direction::天頂余弦と方位の割合から接空間の向きを組む;
use super::tangent_basis::{接基底の向きを戻す, 接基底を組む};

/// 標本1つから半ベクトルを求める。前提: 法線は長さ1に正規化されている。
pub fn ggxの半ベクトルを標本する(標本: [f64; 2], 粗さ: 粗さ, 法線: [f64; 3]) -> [f64; 3] {
    let 広がり = 粗さ.分布の広がり();
    let 接空間の向き = 天頂余弦と方位の割合から接空間の向きを組む(天頂余弦を求める(標本[0], 広がり), 標本[1]);
    接基底の向きを戻す(接基底を組む(法線), 法線, 接空間の向き)
}

/// 分布の累積を逆に解いて天頂余弦を求める。広がりが0のとき分母と分子がともに1-標本になるため、
/// 余弦は1(半ベクトルが法線と一致する完全な鏡面)になる。
fn 天頂余弦を求める(標本: f64, 広がり: f64) -> f64 {
    let 分母 = 1.0 + (広がり * 広がり - 1.0) * 標本;
    if 分母 <= 0.0 {
        return 1.0;
    }
    ((1.0 - 標本) / 分母).clamp(0.0, 1.0).sqrt()
}

/// 半ベクトルで視線を反射させて光の向きを求める。視線と法線が一致する前提の畳み込みでも、
/// BRDF積分表の斜めの視線でも同じ式である。
pub fn 半ベクトルで反射させる(視線: [f64; 3], 半ベクトル: [f64; 3]) -> [f64; 3] {
    let 内積 = 視線[0] * 半ベクトル[0] + 視線[1] * 半ベクトル[1] + 視線[2] * 半ベクトル[2];
    let mut 光の向き = [0.0_f64; 3];
    for 添字 in 0..3 {
        光の向き[添字] = 2.0 * 内積 * 半ベクトル[添字] - 視線[添字];
    }
    光の向き
}
