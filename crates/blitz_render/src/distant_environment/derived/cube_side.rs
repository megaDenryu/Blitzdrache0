//! 立方体画像1面の一辺のテクセル数という量そのもの。触れる状態を持たず、担うのは値域の保証と、
//! 一辺から導ける2つの数(1面のテクセル数・6面の合計)を1箇所で決めることだけである。
//!
//! 遠方環境の解像度と別の型にするのは、あちらが「遠方環境をどれだけ細かく焼くか」という品質方針であり、
//! こちらが方針の中身に使われる量だからである。派生表現は拡散照度と鏡面畳込みの段ごとに別々の一辺を持ち、
//! そのすべてが同じ導出(1面のテクセル数・6面の合計)を要る。

use crate::atmosphere::立方体の面数;

use super::error::派生表現エラー;

/// 立方体画像1面の一辺のテクセル数。
/// 不変条件: 一辺は2以上である(1テクセルの面は面内位置の補間ができない)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 立方体画像の一辺 {
    値: u32,
}

impl 立方体画像の一辺 {
    pub fn 生成する(値: u32) -> Result<Self, 派生表現エラー> {
        if 値 < 2 {
            return Err(派生表現エラー::整数値域外("立方体画像の一辺", 値));
        }
        Ok(Self { 値 })
    }

    pub fn 値(self) -> u32 {
        self.値
    }

    pub fn 面のテクセル数(self) -> usize {
        let 一辺 = usize::try_from(self.値).unwrap_or_else(|_| panic!("立方体画像の一辺{}がusizeに収まらない", self.値));
        一辺 * 一辺
    }

    /// 6面ぶんの合計。読み戻しの受け皿の容量と、焼いた期待値の並びの長さがこの値である。
    pub fn 全テクセル数(self) -> usize {
        let 面数 = usize::try_from(立方体の面数).unwrap_or_else(|_| panic!("立方体の面数{立方体の面数}がusizeに収まらない"));
        self.面のテクセル数() * 面数
    }
}
