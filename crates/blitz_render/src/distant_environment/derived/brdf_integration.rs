//! 反射率積分表の1テクセルの値を求める工程と、表全体の焼き上げ。受け取るのは解像度とテクセルの添字、
//! 返すのは分割和の第2項の2成分である。
//!
//! 第1成分は垂直入射の反射率に掛かる倍率、第2成分は反射率に依らず足す量であり、標準PBRは
//! 垂直入射の反射率×第1成分+第2成分を鏡面の畳み込みへ掛ける。表そのものは大気にも時刻にも依らないため、
//! レンダラーの生成時に1度だけ焼き、鍵の更新では焼き直さない
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「遠方環境の形式と生成(3-Ia)」)。
//!
//! 注意: この式は`shaders/brdf_integration.slang`の写しを持つ。ここが正本である。

use super::brdf_axis::{法線と視線の余弦を求める, 粗さを求める};
use super::brdf_resolution::反射率積分表の解像度;
use super::error::派生表現エラー;
use super::ggx_sample::{ggxの半ベクトルを標本する, 半ベクトルで反射させる};
use super::hammersley::ハンマーズリー標本を求める;
use super::roughness::粗さ;

/// 1テクセルあたりの標本数。
/// 注意: `shaders/brdf_integration.slang`の`brdfIntegrationSampleCount`と一致させる(`cargo xtask conform`が検査する)。
pub const 反射率積分表の標本数: u32 = 256;

pub fn 反射率積分表のテクセル値(
    解像度: 反射率積分表の解像度, 横: u32, 縦: u32
) -> Result<[f64; 2], 派生表現エラー> {
    Ok(積分する(
        法線と視線の余弦を求める(横, 解像度),
        粗さを求める(縦, 解像度)?,
        反射率積分表の標本数,
    ))
}

/// 表全体を走査する。並びは縦が外、横が速い。GPUの2次元画像を読み戻した並びと一致する。
pub fn 反射率積分表を焼く(解像度: 反射率積分表の解像度) -> Result<Vec<[f64; 2]>, 派生表現エラー> {
    let mut 一覧 = Vec::with_capacity(解像度.全テクセル数());
    for 縦 in 0..解像度.縦() {
        for 横 in 0..解像度.横() {
            一覧.push(反射率積分表のテクセル値(解像度, 横, 縦)?);
        }
    }
    Ok(一覧)
}

/// 標本数を指定して積分する。検収が高い標本数の参照値を求めるのに使うため、標本数を引数に持つ。
/// 法線を第三軸に取り、視線を第一軸と第三軸の作る平面へ置く。
pub fn 積分する(法線と視線の余弦: f64, 粗さ: 粗さ, 標本数: u32) -> [f64; 2] {
    let 法線 = [0.0, 0.0, 1.0];
    let 横成分 = (1.0 - 法線と視線の余弦 * 法線と視線の余弦).max(0.0).sqrt();
    let 視線 = [横成分, 0.0, 法線と視線の余弦];
    let mut 倍率の総和 = 0.0_f64;
    let mut 加算量の総和 = 0.0_f64;
    for 添字 in 0..標本数 {
        let 半ベクトル = ggxの半ベクトルを標本する(ハンマーズリー標本を求める(添字, 標本数), 粗さ, 法線);
        let 光の向き = 半ベクトルで反射させる(視線, 半ベクトル);
        if 光の向き[2] <= 0.0 {
            continue;
        }
        let 視線と半ベクトルの余弦 = (視線[0] * 半ベクトル[0] + 視線[2] * 半ベクトル[2]).max(0.0);
        let 可視率 = 可視率を求める(法線と視線の余弦, 光の向き[2], 半ベクトル[2].max(0.0), 視線と半ベクトルの余弦, 粗さ);
        let 反射率の減り = (1.0 - 視線と半ベクトルの余弦).powi(5);
        倍率の総和 += (1.0 - 反射率の減り) * 可視率;
        加算量の総和 += 反射率の減り * 可視率;
    }
    let 逆数 = 1.0 / f64::from(標本数);
    [倍率の総和 * 逆数, 加算量の総和 * 逆数]
}

/// Smithの遮蔽項を標本の密度で割った量。遮蔽の係数に粗さの二乗の半分を取るのは、
/// 遠方環境の畳み込み向けの取り方であり、直接光向けの取り方とは別である。
fn 可視率を求める(
    法線と視線の余弦: f64, 法線と光の余弦: f64, 法線と半ベクトルの余弦: f64, 視線と半ベクトルの余弦: f64, 粗さ: 粗さ
) -> f64 {
    let 係数 = 粗さ.分布の広がり() * 0.5;
    let 遮蔽 = 片側の遮蔽(法線と視線の余弦, 係数) * 片側の遮蔽(法線と光の余弦, 係数);
    let 分母 = 法線と半ベクトルの余弦 * 法線と視線の余弦;
    if 分母 <= 0.0 {
        return 0.0;
    }
    遮蔽 * 視線と半ベクトルの余弦 / 分母
}

fn 片側の遮蔽(余弦: f64, 係数: f64) -> f64 {
    let 分母 = 余弦 * (1.0 - 係数) + 係数;
    if 分母 <= 0.0 {
        return 0.0;
    }
    余弦 / 分母
}
