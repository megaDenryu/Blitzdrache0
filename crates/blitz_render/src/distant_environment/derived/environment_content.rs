//! 遠方環境の立方体画像の中身をCPU側で保持する値。担うのは全テクセルの健全性の保証と、向き1本での参照である。
//!
//! 焼いた結果の列を生のまま持ち回さずこの型に包むのは、派生表現の畳み込みが入力の健全性(有限・非負・面数ぶんの長さ)に
//! 依存するためである。壊れた入力を畳み込むと出力の壊れが入力由来か畳み込み由来か見分けられなくなる。
//!
//! 保持するのは太陽の放射照度と夜空放射輝度を掛けた後の値であり、参照する側は尺度を知らずに読める
//! (参照: `_doc/計画/ユビキタス言語.md`「遠方環境」)。

use super::cube_side::立方体画像の一辺;
use super::cube_texel_lookup::{向きから立方体テクセルを求める, 立方体テクセルの通し番号};
use super::error::派生表現エラー;
use crate::atmosphere::立方体の面;

/// 遠方環境の全テクセル。並びは面(層番号の順)が最も外、次に縦、横が最も速い。
/// 不変条件: 要素数は6面ぶんであり、全成分が有限かつ0以上である。
#[derive(Debug, Clone, PartialEq)]
pub struct 遠方環境の内容 {
    面の一辺: 立方体画像の一辺,
    テクセル一覧: Vec<[f64; 3]>,
}

impl 遠方環境の内容 {
    pub fn 生成する(面の一辺: 立方体画像の一辺, テクセル一覧: Vec<[f64; 3]>) -> Result<Self, 派生表現エラー> {
        let 期待 = 面の一辺.全テクセル数();
        if テクセル一覧.len() != 期待 {
            return Err(派生表現エラー::要素数不一致("遠方環境の内容", 期待, テクセル一覧.len()));
        }
        for テクセル in &テクセル一覧 {
            for 値 in テクセル {
                if !値.is_finite() || *値 < 0.0 {
                    return Err(派生表現エラー::値域外("遠方環境の内容の放射輝度", 値を狭める(*値)));
                }
            }
        }
        Ok(Self {
            面の一辺, テクセル一覧
        })
    }

    pub fn 面の一辺(&self) -> 立方体画像の一辺 {
        self.面の一辺
    }

    pub fn テクセル一覧(&self) -> &[[f64; 3]] {
        &self.テクセル一覧
    }

    pub fn テクセル(&self, 面: 立方体の面, 横: u32, 縦: u32) -> [f64; 3] {
        let 通し番号 = 立方体テクセルの通し番号(面, 横, 縦, self.面の一辺.値());
        let Some(テクセル) = self.テクセル一覧.get(通し番号) else {
            panic!("遠方環境の内容の範囲外を参照した(層{} 横{横} 縦{縦})", 面.層番号());
        };
        *テクセル
    }

    /// GPUの画像が実際に保つ値へ丸めた同じ内容。画素形式が半精度であるため、ホストが与えた倍精度の値は
    /// GPUへ載る時点で丸められる。畳み込みの正本にこの丸めた内容を入れることで、CPUとGPUの差から
    /// 入力の丸めが消え、残る差が写しの誤りだけになる。
    pub fn 半精度へ丸める(&self) -> Result<Self, 派生表現エラー> {
        let 丸めた = self
            .テクセル一覧
            .iter()
            .map(|テクセル| テクセル.map(crate::numeric::half_precision::倍精度を半精度へ丸める))
            .collect();
        Self::生成する(self.面の一辺, 丸めた)
    }

    /// 向き1本が指すテクセルの値。畳み込みが標本ごとにこれを呼ぶ。
    pub fn 向きの値を参照する(&self, 向き: [f64; 3]) -> [f64; 3] {
        let (面, 横, 縦) = 向きから立方体テクセルを求める(向き, self.面の一辺.値());
        self.テクセル(面, 横, 縦)
    }
}

/// 値域を外れた値をエラーへ載せるための単精度化。非有限も含めて報告するため、値そのものの再現性より
/// 人が読めることを優先する。
fn 値を狭める(値: f64) -> f32 {
    glam::DVec3::splat(値).as_vec3().x
}
