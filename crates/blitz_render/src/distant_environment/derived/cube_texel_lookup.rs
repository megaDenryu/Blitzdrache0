//! 向きから立方体画像のテクセルの添字を求める工程。受け取るのは向きと1面の一辺、返すのは面と面内の添字の組である。
//!
//! 補間せず1テクセルだけを読むのは、CPUの正本とシェーダーの写しが同じ値を返すことを最優先するためである。
//! ハードウェアの立方体の補間は面の境界をまたいで混ぜるため、CPU側で同じ結果を再現できず、写しの誤りと
//! 補間の違いを見分けられなくなる。畳み込みが広い立体角にわたって多数の標本を平均するため、
//! 1テクセルずつ読んでも結果のむらは標本数で押さえられる。
//!
//! 注意: この参照は`shaders/distant_environment_lookup.slang`の写しを持つ。ここが正本である。

use crate::atmosphere::{向きから面と面内位置を求める, 立方体の面};
use crate::floor_index::実数位置の床の添字;

/// 向きが指すテクセルの面と面内の添字。長さ0の向きは面を選べないため、その到達はプログラムの誤りである。
pub fn 向きから立方体テクセルを求める(向き: [f64; 3], 一辺: u32) -> (立方体の面, u32, u32) {
    let Some((面, 横位置, 縦位置)) = 向きから面と面内位置を求める(向き) else {
        panic!("長さ0の向きで立方体テクセルを参照した(標本の向きは常に単位ベクトルでなければならない)");
    };
    (面, 面内位置の添字(横位置, 一辺), 面内位置の添字(縦位置, 一辺))
}

/// 0から1までの面内位置を、その位置を含むテクセルの添字へ落とす。位置1はちょうど面の端であるため末尾のテクセルへ寄せる。
fn 面内位置の添字(位置: f64, 一辺: u32) -> u32 {
    実数位置の床の添字(位置 * f64::from(一辺), 一辺 - 1)
}

/// 面と面内の添字から、そのテクセルが立方体画像の並びの中で何番目かを求める。
/// 並びは面(層番号の順)が最も外、次に縦、横が最も速い。焼く側と読み戻す側が同じ並びを使う。
pub fn 立方体テクセルの通し番号(面: 立方体の面, 横: u32, 縦: u32, 一辺: u32) -> usize {
    let 面のテクセル数 = 面内の要素数(一辺) * 面内の要素数(一辺);
    let 層 = usize::try_from(面.層番号()).unwrap_or_else(|_| panic!("立方体の層番号がusizeに収まらない"));
    層 * 面のテクセル数 + 面内の要素数(縦) * 面内の要素数(一辺) + 面内の要素数(横)
}

fn 面内の要素数(値: u32) -> usize {
    usize::try_from(値).unwrap_or_else(|_| panic!("立方体テクセルの添字{値}がusizeに収まらない"))
}
