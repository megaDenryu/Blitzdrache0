//! 拡散照度の立方体画像を何テクセルで焼くかの品質方針。
//!
//! 鏡面畳込みの解像度と別の型にするのは、拡散が段を1つしか持たない一方で鏡面が粗さの段ぶんの縮小列を持ち、
//! 導ける量が違うためである。1つの型へ混ぜると、拡散側に意味のない段番号の引数が付く。
//!
//! 既定の32は、Lambert核の畳み込みが遠方環境の細部をすべて均してしまうため、これ以上細かく焼いても
//! 結果が変わらないことによる(参照: `_doc/設計/放射輝度問い合わせ階層.md`「派生表現(3-Ib)」)。

use super::cube_side::立方体画像の一辺;
use super::error::派生表現エラー;

/// 拡散照度の立方体画像の解像度。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 拡散照度の解像度 {
    面の一辺: 立方体画像の一辺,
}

impl 拡散照度の解像度 {
    pub fn 生成する(面の一辺: u32) -> Result<Self, 派生表現エラー> {
        Ok(Self {
            面の一辺: 立方体画像の一辺::生成する(面の一辺)?,
        })
    }

    pub fn 既定値() -> Self {
        Self {
            面の一辺: 既定の面の一辺()
        }
    }

    pub fn 面の一辺(self) -> 立方体画像の一辺 {
        self.面の一辺
    }
}

/// 既定値の生成が失敗しえないことをこの関数が担う。32は2以上であるため、値域の検証は必ず通る。
fn 既定の面の一辺() -> 立方体画像の一辺 {
    立方体画像の一辺::生成する(32).unwrap_or_else(|誤り| panic!("拡散照度の既定の一辺が値域を外れた: {誤り}"))
}
