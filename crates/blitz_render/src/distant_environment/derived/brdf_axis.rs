//! 反射率積分表のテクセルの添字と2つの軸の値との行き来を担う工程。受け取るのは添字と辺の長さ、
//! 返すのは法線と視線の余弦または粗さである。
//!
//! テクセル中心を軸の値に取るのは、参照する側が余弦と粗さをそのままUVとして標本するためである。
//! 焼く側が端から端の目盛りを使い参照する側が中心の目盛りを使うと、表の値が半テクセルぶんずれる。
//!
//! 注意: この写像は`shaders/brdf_integration.slang`の写しを持つ。ここが正本である。

use super::brdf_resolution::反射率積分表の解像度;
use super::error::派生表現エラー;
use super::roughness::粗さ;

/// 横の添字から法線と視線の余弦を求める。0にも1にもならないため、視線が面と平行になる特異点を踏まない。
pub fn 法線と視線の余弦を求める(横: u32, 解像度: 反射率積分表の解像度) -> f64 {
    テクセル中心の割合(横, 解像度.横())
}

/// 縦の添字から粗さを求める。テクセル中心であるため0より大きく1より小さい。
pub fn 粗さを求める(縦: u32, 解像度: 反射率積分表の解像度) -> Result<粗さ, 派生表現エラー> {
    粗さ::生成する(単精度へ狭める(テクセル中心の割合(縦, 解像度.縦())))
}

fn テクセル中心の割合(添字: u32, 辺の長さ: u32) -> f64 {
    (f64::from(添字) + 0.5) / f64::from(辺の長さ)
}

/// 粗さの値オブジェクトが単精度で持つため、割合を狭める。値域は0から1の内側であり、狭めても値域を出ない。
fn 単精度へ狭める(値: f64) -> f32 {
    glam::DVec3::splat(値).as_vec3().x
}
