//! 鏡面畳込みの立方体画像を何段でどれだけ細かく焼くかの品質方針。段の番号から一辺と粗さを導くのもここが持つ。
//!
//! 段と粗さの対応をこの型が単独で持つのは、焼く側とGPUへ渡す即時定数と検収の期待値の3つが同じ対応を要るためである。
//! 対応が散ると、段を1つ増やしたときに粗さの目盛りだけが古いまま残る。
//!
//! 既定は最詳細段128の6段(128・64・32・16・8・4)であり、粗さは段番号を段数から1を引いた数で割った値である
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「遠方環境の形式と生成(3-Ia)」)。

use super::cube_side::立方体画像の一辺;
use super::error::派生表現エラー;
use super::mip_level::粗さ段;
use super::roughness::粗さ;

/// 段数の上限。段ごとに1本のディスクリプタセットとパスを持つため、無制限には増やせない。
const 粗さ段数の上限: u32 = 16;

/// 鏡面畳込みの立方体画像の解像度と段構成。
/// 不変条件: 段数は2以上かつ上限以下であり、最も粗い段の一辺も2以上である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 鏡面畳込みの解像度 {
    最詳細段の一辺: 立方体画像の一辺,
    粗さ段数: u32,
}

impl 鏡面畳込みの解像度 {
    pub fn 生成する(最詳細段の一辺: u32, 粗さ段数: u32) -> Result<Self, 派生表現エラー> {
        if !(2..=粗さ段数の上限).contains(&粗さ段数) {
            return Err(派生表現エラー::整数値域外("鏡面畳込みの粗さ段数", 粗さ段数));
        }
        let 最詳細段の一辺 = 立方体画像の一辺::生成する(最詳細段の一辺)?;
        let 最も粗い段の一辺 = 最詳細段の一辺.値() >> (粗さ段数 - 1);
        立方体画像の一辺::生成する(最も粗い段の一辺)?;
        Ok(Self {
            最詳細段の一辺, 粗さ段数
        })
    }

    pub fn 既定値() -> Self {
        Self::生成する(128, 6).unwrap_or_else(|誤り| panic!("鏡面畳込みの既定の解像度が値域を外れた: {誤り}"))
    }

    pub fn 粗さ段数(self) -> u32 {
        self.粗さ段数
    }

    /// 段番号の小さい順に並べた全段。焼く側とディスクリプタを組む側が走査に使う。
    pub fn 全段(self) -> Vec<粗さ段> {
        (0..self.粗さ段数).map(粗さ段::生成する).collect()
    }

    pub fn 段の一辺(self, 段: 粗さ段) -> 立方体画像の一辺 {
        let 一辺 = self.最詳細段の一辺.値() >> 段.番号();
        立方体画像の一辺::生成する(一辺).unwrap_or_else(|誤り| panic!("段{}の一辺が値域を外れた: {誤り}", 段.番号()))
    }

    /// 段番号を0から1までの粗さへ写す。最詳細段が0、最も粗い段が1である。
    pub fn 段の粗さ(self, 段: 粗さ段) -> 粗さ {
        let 分子 = u16::try_from(段.番号()).unwrap_or_else(|_| panic!("粗さ段の番号{}がu16に収まらない", 段.番号()));
        let 分母 = u16::try_from(self.粗さ段数 - 1).unwrap_or_else(|_| panic!("粗さ段数{}がu16に収まらない", self.粗さ段数));
        let 値 = f32::from(分子) / f32::from(分母);
        粗さ::生成する(値).unwrap_or_else(|誤り| panic!("段{}の粗さが値域を外れた: {誤り}", 段.番号()))
    }
}
