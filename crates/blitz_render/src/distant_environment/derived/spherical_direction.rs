//! 天頂の余弦と方位の割合から接空間の向きを組む工程。受け取るのは0以上1以下の天頂余弦と0以上1未満の方位の割合、
//! 返すのは第三軸を天頂に取った単位ベクトルである。
//!
//! 拡散照度の余弦分布とGGXの分布は天頂余弦の決め方だけが違い、そこから向きを組む段は同じである。
//! 2箇所へ書くと、一周の定数や正弦の求め方が片方だけ変わったときに2つの畳み込みが別の座標系を使う。
//!
//! 注意: この式は`shaders/sampling_math.slang`の`tangentSpaceDirection`の写しを持つ。ここが正本である。

use std::f64::consts::TAU;

pub fn 天頂余弦と方位の割合から接空間の向きを組む(天頂余弦: f64, 方位の割合: f64) -> [f64; 3] {
    let 天頂正弦 = (1.0 - 天頂余弦 * 天頂余弦).max(0.0).sqrt();
    let 方位 = TAU * 方位の割合;
    [天頂正弦 * 方位.cos(), 天頂正弦 * 方位.sin(), 天頂余弦]
}
