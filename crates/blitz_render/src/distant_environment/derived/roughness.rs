//! 表面の粗さという量そのもの。触れる状態を持たず、担うのは値域の保証と、法線分布の広がりを表す係数への変換である。
//!
//! 粗さと係数を別の値にするのは、鏡面の畳み込みとBRDF積分表の両方が「粗さの二乗を係数に取る」という同じ規約に
//! 従わなければならないためである。二乗を掛ける場所が2箇所へ散ると、片方だけ規約を変えたときに
//! 畳み込んだ画像と積分表が別の粗さを表す。

use super::error::派生表現エラー;

/// 表面の粗さ。0が完全な鏡面、1が最も拡散した反射である。
/// 不変条件: 有限かつ0以上1以下である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 粗さ {
    値: f32,
}

impl 粗さ {
    pub fn 生成する(値: f32) -> Result<Self, 派生表現エラー> {
        if !値.is_finite() || !(0.0..=1.0).contains(&値) {
            return Err(派生表現エラー::値域外("粗さ", 値));
        }
        Ok(Self { 値 })
    }

    pub fn 値(self) -> f32 {
        self.値
    }

    /// 法線分布の広がりを表す係数。粗さの二乗であり、GGXの分布と遮蔽項がこの値を使う。
    /// 二乗を取るのは、粗さを見た目の変化が一様になる目盛りとして持つDisneyの規約に合わせるためである。
    pub fn 分布の広がり(self) -> f64 {
        let 値 = f64::from(self.値);
        値 * 値
    }
}
