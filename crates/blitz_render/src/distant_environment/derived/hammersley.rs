//! ハンマーズリー列の1標本を求める工程。受け取るのは標本の添字と標本数、返すのは単位正方形の中の2成分である。
//!
//! 疑似乱数でなくこの列を使うのは、同じ条件で焼けば必ず同じ画素が出ることを保証するためである。焼き直すかどうかを
//! 鍵の比較で決める設計は「同じ鍵なら同じ結果」に依存しており、標本が実行ごとに動くとその前提が崩れる。
//! 一様乱数より偏りが少ないため、同じ標本数でも畳み込みのむらが小さい。
//!
//! 注意: この列は`shaders/hammersley.slang`の写しを持つ。ここが正本である。

/// 2の32乗の逆数。ビットを逆順に読み替えた整数へ掛けると単位区間の中の値になる。
const 二の三十二乗の逆数: f64 = 1.0 / 4_294_967_296.0;

/// 標本1つぶんの2成分。第一成分は添字を標本数で割った等間隔の目盛り、第二成分はビットを逆順に読み替えた値である。
/// 前提: 標本数は1以上である(呼び出し元は畳み込みごとの定数を渡す)。
pub fn ハンマーズリー標本を求める(添字: u32, 標本数: u32) -> [f64; 2] {
    [f64::from(添字) / f64::from(標本数), 基数二の逆順(添字)]
}

/// 添字のビットの並びを逆順に読み替えて単位区間へ写す。添字が1つ増えるたびに区間の空いている側へ点が置かれるため、
/// 標本数がいくつでも区間全体が均されている。
fn 基数二の逆順(添字: u32) -> f64 {
    f64::from(添字.reverse_bits()) * 二の三十二乗の逆数
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::ハンマーズリー標本を求める;

    #[test]
    fn 先頭の標本は原点である() {
        assert_eq!(ハンマーズリー標本を求める(0, 8), [0.0, 0.0]);
    }

    #[test]
    fn 第二成分はビットの逆順である() {
        assert_eq!(ハンマーズリー標本を求める(1, 8)[1], 0.5);
        assert_eq!(ハンマーズリー標本を求める(2, 8)[1], 0.25);
        assert_eq!(ハンマーズリー標本を求める(3, 8)[1], 0.75);
    }

    #[test]
    fn 全標本が単位正方形に収まる() {
        for 添字 in 0..256 {
            let [第一, 第二] = ハンマーズリー標本を求める(添字, 256);
            assert!((0.0..1.0).contains(&第一));
            assert!((0.0..1.0).contains(&第二));
        }
    }
}
