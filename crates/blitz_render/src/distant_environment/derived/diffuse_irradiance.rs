//! 拡散照度の立方体画像の1テクセルの値を求める工程と、6面すべての焼き上げ。受け取るのは遠方環境の内容と解像度と
//! テクセルの位置、返すのはその向きを法線とする面が受ける照度である。
//!
//! 保持する量はLambert核で畳み込んだ後の照度∫L(n・ω)dωであり、反射率を円周率で割った係数は標準PBRの側が掛ける。
//! 名前だけで円周率の有無を伝えると消費側が取り違えるため、量の定義をこの冒頭に置く
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「派生表現(3-Ib)」)。
//!
//! 余弦に比例した密度で標本するため、標本ごとの重みが円周率1つに畳まれる。定数の放射輝度Lを入力すると
//! 結果は必ず円周率×Lになり、この性質が検収の解析的な判定になる。
//!
//! 注意: この式は`shaders/diffuse_irradiance.slang`の写しを持つ。ここが正本である。

use std::f64::consts::PI;

use super::diffuse_resolution::拡散照度の解像度;
use super::environment_content::遠方環境の内容;
use super::hammersley::ハンマーズリー標本を求める;
use super::spherical_direction::天頂余弦と方位の割合から接空間の向きを組む;
use super::tangent_basis::{接基底の向きを戻す, 接基底を組む};
use crate::atmosphere::{テクセル中心の面内位置, 立方体の全面, 立方体の面, 面と面内位置から向きを求める};

/// 1テクセルあたりの標本数。値を上げると畳み込みのむらが減り、更新の費用が比例して増える。
/// 注意: `shaders/diffuse_irradiance.slang`の`diffuseIrradianceSampleCount`と一致させる(`cargo xtask conform`が検査する)。
pub const 拡散照度の標本数: u32 = 256;

pub fn 拡散照度のテクセル値(
    環境: &遠方環境の内容, 解像度: 拡散照度の解像度, 面: 立方体の面, 横: u32, 縦: u32
) -> [f64; 3] {
    let 一辺 = 解像度.面の一辺().値();
    let 法線 = 面と面内位置から向きを求める(面, テクセル中心の面内位置(横, 一辺), テクセル中心の面内位置(縦, 一辺));
    let 接基底 = 接基底を組む(法線);
    let mut 合計 = [0.0_f64; 3];
    for 添字 in 0..拡散照度の標本数 {
        let 標本 = ハンマーズリー標本を求める(添字, 拡散照度の標本数);
        let 向き = 接基底の向きを戻す(接基底, 法線, 余弦分布の接空間の向き(標本));
        let 値 = 環境.向きの値を参照する(向き);
        for 成分 in 0..3 {
            合計[成分] += 値[成分];
        }
    }
    let 係数 = PI / f64::from(拡散照度の標本数);
    [合計[0] * 係数, 合計[1] * 係数, 合計[2] * 係数]
}

/// 6面すべてを走査する。並びは面(層番号の順)が最も外、次に縦、横が最も速い。
pub fn 拡散照度を焼く(環境: &遠方環境の内容, 解像度: 拡散照度の解像度) -> Vec<[f64; 3]> {
    let 一辺 = 解像度.面の一辺().値();
    let mut 一覧 = Vec::with_capacity(解像度.面の一辺().全テクセル数());
    for 面 in 立方体の全面 {
        for 縦 in 0..一辺 {
            for 横 in 0..一辺 {
                一覧.push(拡散照度のテクセル値(環境, 解像度, 面, 横, 縦));
            }
        }
    }
    一覧
}

/// 余弦に比例した密度で半球を標本する接空間の向き。第一成分の平方根の補数を天頂余弦に取ると、
/// 密度が余弦を円周率で割った形になり、標本ごとの重みが円周率1つへ畳まれる。
fn 余弦分布の接空間の向き(標本: [f64; 2]) -> [f64; 3] {
    天頂余弦と方位の割合から接空間の向きを組む((1.0 - 標本[0]).max(0.0).sqrt(), 標本[1])
}
