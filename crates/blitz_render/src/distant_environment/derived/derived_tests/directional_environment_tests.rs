//! 方向性の強い環境を入れたときの性質を確かめる。担うのは、粗さを上げるほど鏡面畳込みのばらつきが減ることと、
//! 最詳細段が遠方環境そのものであることの2つである。
//!
//! ばらつきの単調な減りは、粗さが標本の広がりへ効いていることの証拠である。粗さを読み落とすと
//! どの段も同じ画像になり、絵では「反射がぼけない」という形でしか現れない。

use crate::cube_image::{立方体の全面, 立方体の面};
use crate::distant_environment::derived::{
    方向性の強い遠方環境, 立方体画像の一辺, 鏡面畳込みのテクセル値, 鏡面畳込みの段を焼く, 鏡面畳込みの解像度
};

#[test]
fn 粗さが上がるほど鏡面畳込みのばらつきが減る() {
    let 一辺 = 立方体画像の一辺::生成する(16).unwrap();
    let 環境 = 方向性の強い遠方環境(一辺).unwrap();
    let 解像度 = 鏡面畳込みの解像度::生成する(16, 4).unwrap();
    let mut 前の分散 = f64::INFINITY;
    for 段 in 解像度.全段() {
        let 分散 = 緑成分の分散(&鏡面畳込みの段を焼く(&環境, 解像度, 段));
        assert!(分散 < 前の分散, "段{}の分散{分散}が前の段の{前の分散}以上である", 段.番号());
        前の分散 = 分散;
    }
}

#[test]
fn 最詳細段は遠方環境のテクセルそのものである() {
    let 一辺 = 立方体画像の一辺::生成する(8).unwrap();
    let 環境 = 方向性の強い遠方環境(一辺).unwrap();
    let 解像度 = 鏡面畳込みの解像度::生成する(8, 3).unwrap();
    let 最詳細段 = 解像度.全段()[0];
    for 面 in 立方体の全面 {
        for 縦 in 0..8 {
            for 横 in 0..8 {
                assert_eq!(鏡面畳込みのテクセル値(&環境, 解像度, 最詳細段, 面, 横, 縦), 環境.テクセル(面, 横, 縦));
            }
        }
    }
}

#[test]
fn 方向性の強い環境は面ごとに違う明るさを持つ() {
    let 一辺 = 立方体画像の一辺::生成する(8).unwrap();
    let 環境 = 方向性の強い遠方環境(一辺).unwrap();
    let 天頂 = 環境.テクセル(立方体の面::第二軸の正, 4, 4)[1];
    let 天底 = 環境.テクセル(立方体の面::第二軸の負, 4, 4)[1];
    assert!(天頂 > 天底 * 10.0, "天頂{天頂}が天底{天底}に対して十分明るくない");
}

fn 緑成分の分散(テクセル一覧: &[[f64; 3]]) -> f64 {
    let 件数 = f64::from(u32::try_from(テクセル一覧.len()).unwrap());
    let 平均 = テクセル一覧.iter().map(|テクセル| テクセル[1]).sum::<f64>() / 件数;
    テクセル一覧
        .iter()
        .map(|テクセル| (テクセル[1] - 平均) * (テクセル[1] - 平均))
        .sum::<f64>()
        / 件数
}
