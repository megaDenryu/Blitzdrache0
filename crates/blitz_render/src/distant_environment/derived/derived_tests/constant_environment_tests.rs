//! 定数の放射輝度を入れたときの解析解を確かめる。担うのは、拡散照度が円周率×放射輝度になることと、
//! 鏡面畳込みがどの粗さ段でも放射輝度そのものになることの2つである。
//!
//! この2つは標本の重みの規約が正しいことの証拠である。重みの正規化を誤ると、環境が一様でも
//! 結果が放射輝度の定数倍だけずれ、絵では明るさの違いにしか見えない。

use super::定数の環境;
use crate::atmosphere::立方体の全面;
use crate::distant_environment::derived::{
    拡散照度のテクセル値, 拡散照度の解像度, 鏡面畳込みのテクセル値, 鏡面畳込みの解像度
};

const 検査する放射輝度: [f64; 3] = [0.25, 1.5, 3.75];

#[test]
fn 定数環境の拡散照度は円周率倍になる() {
    let 環境 = 定数の環境(16, 検査する放射輝度);
    let 解像度 = 拡散照度の解像度::生成する(8).unwrap();
    for 面 in 立方体の全面 {
        let 値 = 拡散照度のテクセル値(&環境, 解像度, 面, 3, 5);
        for 成分 in 0..3 {
            let 期待 = std::f64::consts::PI * 検査する放射輝度[成分];
            assert!((値[成分] - 期待).abs() < 1.0e-12, "面{面:?}の成分{成分}が{}で期待{期待}と違う", 値[成分]);
        }
    }
}

#[test]
fn 定数環境の鏡面畳込みは全粗さ段で放射輝度そのものになる() {
    let 環境 = 定数の環境(32, 検査する放射輝度);
    let 解像度 = 鏡面畳込みの解像度::生成する(32, 5).unwrap();
    for 段 in 解像度.全段() {
        let 値 = 鏡面畳込みのテクセル値(&環境, 解像度, 段, 立方体の全面[2], 1, 1);
        for 成分 in 0..3 {
            let 差 = (値[成分] - 検査する放射輝度[成分]).abs();
            assert!(
                差 < 1.0e-12,
                "段{}の成分{成分}が{}で期待{}と違う",
                段.番号(),
                値[成分],
                検査する放射輝度[成分]
            );
        }
    }
}

#[test]
fn 定数を変えると拡散照度も同じ倍率で変わる() {
    let 倍率 = 4.0;
    let 一倍 = 定数の環境(8, 検査する放射輝度);
    let 四倍 = 定数の環境(8, [検査する放射輝度[0] * 倍率, 検査する放射輝度[1] * 倍率, 検査する放射輝度[2] * 倍率]);
    let 解像度 = 拡散照度の解像度::生成する(4).unwrap();
    let 基準 = 拡散照度のテクセル値(&一倍, 解像度, 立方体の全面[0], 1, 2);
    let 対照 = 拡散照度のテクセル値(&四倍, 解像度, 立方体の全面[0], 1, 2);
    for 成分 in 0..3 {
        assert!((対照[成分] - 基準[成分] * 倍率).abs() < 1.0e-12);
    }
}
