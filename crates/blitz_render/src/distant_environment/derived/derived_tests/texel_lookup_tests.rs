//! 立方体テクセルの参照と接基底の性質を確かめる。担うのは、テクセル中心の向きを参照するとそのテクセル自身が
//! 返ることと、接基底が正規直交であることの2つである。
//!
//! 前者は焼く側の写像と参照する側の写像が互いの逆であることの証拠であり、これが崩れると畳み込みが
//! 隣のテクセルを読み続ける。

use crate::cube_image::{テクセル中心の面内位置, 立方体の全面, 面と面内位置から向きを求める};
use crate::distant_environment::derived::{向きから立方体テクセルを求める, 立方体テクセルの通し番号};

#[test]
fn テクセル中心の向きは自分自身の添字へ戻る() {
    let 一辺 = 16;
    for 面 in 立方体の全面 {
        for 縦 in 0..一辺 {
            for 横 in 0..一辺 {
                let 向き = 面と面内位置から向きを求める(面, テクセル中心の面内位置(横, 一辺), テクセル中心の面内位置(縦, 一辺));
                assert_eq!(向きから立方体テクセルを求める(向き, 一辺), (面, 横, 縦));
            }
        }
    }
}

#[test]
fn 通し番号は面と縦と横の順に並ぶ() {
    let 一辺 = 4;
    assert_eq!(立方体テクセルの通し番号(立方体の全面[0], 0, 0, 一辺), 0);
    assert_eq!(立方体テクセルの通し番号(立方体の全面[0], 1, 0, 一辺), 1);
    assert_eq!(立方体テクセルの通し番号(立方体の全面[0], 0, 1, 一辺), 4);
    assert_eq!(立方体テクセルの通し番号(立方体の全面[1], 0, 0, 一辺), 16);
}

#[test]
fn 接基底は法線と直交し互いにも直交する() {
    let 一辺 = 8;
    for 面 in 立方体の全面 {
        for 縦 in 0..一辺 {
            for 横 in 0..一辺 {
                let 法線 = 面と面内位置から向きを求める(面, テクセル中心の面内位置(横, 一辺), テクセル中心の面内位置(縦, 一辺));
                let [第一, 第二] = crate::distant_environment::derived::接基底を組む(法線);
                assert!(内積(第一, 法線).abs() < 1.0e-12);
                assert!(内積(第二, 法線).abs() < 1.0e-12);
                assert!(内積(第一, 第二).abs() < 1.0e-12);
                assert!((内積(第一, 第一) - 1.0).abs() < 1.0e-12);
                assert!((内積(第二, 第二) - 1.0).abs() < 1.0e-12);
            }
        }
    }
}

fn 内積(左: [f64; 3], 右: [f64; 3]) -> f64 {
    左[0] * 右[0] + 左[1] * 右[1] + 左[2] * 右[2]
}
