//! 反射率積分表の性質を確かめる。担うのは、値域(有限・非負・分割和の第1項が1を超えないこと)と、
//! 標本数を上げたときに値が収束することの2つである。
//!
//! 収束を見るのは、検収がGPUの256標本を高い標本数のCPU参照と突き合わせるためである。収束していなければ、
//! GPUとCPUの差が写しの誤りなのか標本数の違いなのか区別できない。

use crate::distant_environment::derived::{
    反射率積分表のテクセル値, 反射率積分表の解像度, 反射率積分表を焼く, 法線と視線の余弦を求める, 積分する, 粗さを求める,
};

/// 収束の参照に使う標本数。焼き上げの256に対して16倍を取る。
const 高い標本数: u32 = 4096;

#[test]
fn 全テクセルが有限かつ非負である() {
    let 解像度 = 反射率積分表の解像度::生成する(16, 16).unwrap();
    let 焼いた = 反射率積分表を焼く(解像度).unwrap();
    assert_eq!(焼いた.len(), 解像度.全テクセル数());
    for (通し番号, テクセル) in 焼いた.iter().enumerate() {
        for 成分 in テクセル {
            assert!(成分.is_finite() && *成分 >= 0.0, "{通し番号}番目の成分が{成分}である");
        }
        assert!(テクセル[0] <= 1.0 + 1.0e-6, "{通し番号}番目の倍率{}が1を超えた", テクセル[0]);
    }
}

/// 焼き上げの並びが縦を外、横を速くしていることを確かめる。読み戻しの並びと食い違うと、
/// 表の代表テクセルの突き合わせが別の位置どうしを比べる。
#[test]
fn 焼き上げの並びは縦が外で横が速い() {
    let 解像度 = 反射率積分表の解像度::生成する(8, 4).unwrap();
    let 焼いた = 反射率積分表を焼く(解像度).unwrap();
    for 縦 in 0..解像度.縦() {
        for 横 in 0..解像度.横() {
            let 通し番号 = usize::try_from(縦 * 解像度.横() + 横).unwrap();
            assert_eq!(焼いた[通し番号], 反射率積分表のテクセル値(解像度, 横, 縦).unwrap());
        }
    }
}

#[test]
fn 焼き上げの標本数は高い標本数へ収束している() {
    let 解像度 = 反射率積分表の解像度::既定値();
    let 見る位置 = [
        (0, 0),
        (解像度.横() - 1, 0),
        (0, 解像度.縦() - 1),
        (解像度.横() - 1, 解像度.縦() - 1),
        (128, 128),
    ];
    for (横, 縦) in 見る位置 {
        let 焼いた値 = 反射率積分表のテクセル値(解像度, 横, 縦).unwrap();
        let 参照 = 積分する(法線と視線の余弦を求める(横, 解像度), 粗さを求める(縦, 解像度).unwrap(), 高い標本数);
        for 成分 in 0..2 {
            let 差 = (焼いた値[成分] - 参照[成分]).abs();
            assert!(
                差 < 2.0e-2,
                "横{横} 縦{縦} 成分{成分}の差{差}が大きい(焼いた{} 参照{})",
                焼いた値[成分],
                参照[成分]
            );
        }
    }
}

#[test]
fn 粗さ0では入射角に依らず倍率が1に近い() {
    let 解像度 = 反射率積分表の解像度::生成する(64, 64).unwrap();
    for 横 in [8, 32, 63] {
        let 値 = 反射率積分表のテクセル値(解像度, 横, 0).unwrap();
        assert!(値[0] > 0.5, "横{横}の倍率{}が小さすぎる", 値[0]);
    }
}
