//! 鏡面畳込みの立方体画像の1テクセルの値を求める工程と、1つの粗さ段の焼き上げ。受け取るのは遠方環境の内容と
//! 解像度と段とテクセルの位置、返すのはその向きへ反射する光の畳み込み後の放射輝度である。
//!
//! 法線と視線と反射方向をすべてテクセルの向きに等しいと仮定するのは、畳み込みの入力が方向1つしか持てないためである。
//! 斜めから見たときの反射の伸びはこの仮定で失われるが、分割和の近似としてこれが標準の構成である。
//!
//! 標本ごとの重みが法線と光の余弦だけになり、その総和で割った加重平均になる。定数の放射輝度Lを入力すると
//! どの粗さ段の結果も必ずLになり、この性質が検収の解析的な判定になる。
//!
//! 最詳細段が遠方環境の複製であるのは、粗さ0の畳み込みが元の画像そのものだからである。GPU側はこの段を
//! 計算でなく画像どうしのコピーで作るため、値はビット単位で一致する。
//!
//! 注意: この式は`shaders/specular_prefilter.slang`の写しを持つ。ここが正本である。

use super::environment_content::遠方環境の内容;
use super::ggx_sample::{ggxの半ベクトルを標本する, 半ベクトルで反射させる};
use super::hammersley::ハンマーズリー標本を求める;
use super::mip_level::粗さ段;
use super::specular_resolution::鏡面畳込みの解像度;
use crate::atmosphere::{テクセル中心の面内位置, 立方体の全面, 立方体の面, 面と面内位置から向きを求める};

/// 1テクセルあたりの標本数。
/// 注意: `shaders/specular_prefilter.slang`の`specularPrefilterSampleCount`と一致させる(`cargo xtask conform`が検査する)。
pub const 鏡面畳込みの標本数: u32 = 128;

/// 前提: 最詳細段の値を求めるとき、遠方環境の一辺は最詳細段の一辺と等しい(GPU側は画像どうしのコピーで作るため、
/// この一致が無いとコピー自体が成り立たない)。
pub fn 鏡面畳込みのテクセル値(
    環境: &遠方環境の内容,
    解像度: 鏡面畳込みの解像度,
    段: 粗さ段,
    面: 立方体の面,
    横: u32,
    縦: u32,
) -> [f64; 3] {
    if 段.番号() == 0 {
        return 環境.テクセル(面, 横, 縦);
    }
    let 一辺 = 解像度.段の一辺(段).値();
    let 向き = 面と面内位置から向きを求める(面, テクセル中心の面内位置(横, 一辺), テクセル中心の面内位置(縦, 一辺));
    畳み込む(環境, 解像度.段の粗さ(段), 向き)
}

/// 1つの粗さ段の6面すべてを走査する。並びは面(層番号の順)が最も外、次に縦、横が最も速い。
pub fn 鏡面畳込みの段を焼く(環境: &遠方環境の内容, 解像度: 鏡面畳込みの解像度, 段: 粗さ段) -> Vec<[f64; 3]> {
    let 一辺 = 解像度.段の一辺(段);
    let mut 一覧 = Vec::with_capacity(一辺.全テクセル数());
    for 面 in 立方体の全面 {
        for 縦 in 0..一辺.値() {
            for 横 in 0..一辺.値() {
                一覧.push(鏡面畳込みのテクセル値(環境, 解像度, 段, 面, 横, 縦));
            }
        }
    }
    一覧
}

/// GGXの分布で標本した反射方向の加重平均。重みが0の向きが1つも無いことは粗さが正なら成り立つが、
/// 成り立たなかったときに0を返すと画素が黒く落ちるため、その場合は畳み込まない元の値を返す。
fn 畳み込む(環境: &遠方環境の内容, 粗さ: super::roughness::粗さ, 向き: [f64; 3]) -> [f64; 3] {
    let mut 合計 = [0.0_f64; 3];
    let mut 重みの総和 = 0.0_f64;
    for 添字 in 0..鏡面畳込みの標本数 {
        let 標本 = ハンマーズリー標本を求める(添字, 鏡面畳込みの標本数);
        let 半ベクトル = ggxの半ベクトルを標本する(標本, 粗さ, 向き);
        let 光の向き = 半ベクトルで反射させる(向き, 半ベクトル);
        let 余弦 = 向き[0] * 光の向き[0] + 向き[1] * 光の向き[1] + 向き[2] * 光の向き[2];
        if 余弦 <= 0.0 {
            continue;
        }
        let 値 = 環境.向きの値を参照する(光の向き);
        for 成分 in 0..3 {
            合計[成分] += 値[成分] * 余弦;
        }
        重みの総和 += 余弦;
    }
    if 重みの総和 <= 0.0 {
        return 環境.向きの値を参照する(向き);
    }
    [合計[0] / 重みの総和, 合計[1] / 重みの総和, 合計[2] / 重みの総和]
}
