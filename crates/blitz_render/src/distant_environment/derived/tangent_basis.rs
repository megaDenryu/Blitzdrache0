//! 単位ベクトル1本から正規直交の接基底2本を組む工程。受け取るのは法線、返すのは法線と直交し互いにも直交する
//! 2本の単位ベクトルである。
//!
//! 分岐で上方向を選ぶ素朴な組み方を採らないのは、法線が上方向と平行になる極で外積が0へ潰れ、その近くで
//! 基底が跳ねるためである。ここで使うのはDuffらの方法であり、法線の第三成分の符号だけで場合が分かれ、
//! どの向きでも分母が1以上に保たれる。
//!
//! 標本の方位を決めるのがこの基底であるため、CPUとシェーダーで組み方が違うと同じ標本番号が別の向きを指す。
//! 注意: この組み方は`shaders/tangent_basis.slang`の写しを持つ。ここが正本である。

/// 法線から接基底2本を組む。返す2本と法線は右手系の正規直交基底をなす。
/// 前提: 法線は長さ1に正規化されている。
pub fn 接基底を組む(法線: [f64; 3]) -> [[f64; 3]; 2] {
    let 符号 = if 法線[2] >= 0.0 { 1.0 } else { -1.0 };
    // 分母は法線の第三成分が1のとき2、-1のとき-2であり、符号を合わせているため0にならない。
    let 逆数 = -1.0 / (符号 + 法線[2]);
    let 交差項 = 法線[0] * 法線[1] * 逆数;
    let 第一軸 = [1.0 + 符号 * 法線[0] * 法線[0] * 逆数, 符号 * 交差項, -符号 * 法線[0]];
    let 第二軸 = [交差項, 符号 + 法線[1] * 法線[1] * 逆数, -法線[1]];
    [第一軸, 第二軸]
}

/// 接基底の座標で表した向きをもとの座標へ戻す。第一成分と第二成分が接基底、第三成分が法線に掛かる。
pub fn 接基底の向きを戻す(接基底: [[f64; 3]; 2], 法線: [f64; 3], 接空間の向き: [f64; 3]) -> [f64; 3] {
    let [第一軸, 第二軸] = 接基底;
    let mut 向き = [0.0_f64; 3];
    for 添字 in 0..3 {
        向き[添字] = 第一軸[添字] * 接空間の向き[0] + 第二軸[添字] * 接空間の向き[1] + 法線[添字] * 接空間の向き[2];
    }
    向き
}
