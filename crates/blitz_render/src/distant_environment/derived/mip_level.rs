//! 鏡面畳込みの縮小段の番号という量そのもの。触れる状態を持たず、担うのは「その番号が実在する段を指す」ことの
//! 保証だけである。
//!
//! 生の整数で持たないのは、段の上限が鏡面畳込みの解像度の方針で決まる値であり、番号だけを別の解像度へ
//! 渡せてしまうと存在しない段を焼こうとするためである。生成が解像度の側にしか無いことがそれを防ぐ。

/// 鏡面畳込みの縮小段。0が最詳細(粗さ0)であり、番号が増えるほど粗い。
/// 不変条件: 番号は生成元の鏡面畳込みの解像度が持つ段数より小さい。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 粗さ段 {
    番号: u32,
}

impl 粗さ段 {
    /// 生成を`derived`の内側へ限るのは、番号の上限を知るのが鏡面畳込みの解像度だけだからである。
    pub(super) fn 生成する(番号: u32) -> Self {
        Self { 番号 }
    }

    pub fn 番号(self) -> u32 {
        self.番号
    }
}
