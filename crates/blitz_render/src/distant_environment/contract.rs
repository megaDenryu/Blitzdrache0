//! レンダラー1個につき1つ選ぶ、間接照明の供給元の契約。担当するのは「間接光をどの供給元が答えるかを型で決め、
//! その契約が要る資源が揃っているかを生成の境界で確かめる」ことである。
//!
//! 枝を2つに閉じるのは、実在する供給元が定数近似と遠方環境の2つしか無いためである。2つ目の実在方式が来る前に
//! 汎用の合成器やGPU側の方式のタグを作らない(参照: `_doc/設計/放射輝度問い合わせ階層.md`「品質方式の初期の組(確定)」)。
//!
//! 資源の欠落を無言のfallbackで埋めないのは、「遠方環境を選んだのに定数近似の絵が出る」という、絵にしか現れない
//! 欠陥になるためである。拒む場所をコマンド記録中でなく生成の境界へ置くのは、契約と資源の対応が起動時に1度決まって
//! 以降変わらず、フレームごとに問い直す性質のものではないためである。

use crate::error::空エラー;

/// 間接照明の供給元の契約。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 照明問い合わせ契約 {
    /// 方向も位置も問わない定数間接近似だけで答える。遠方環境と派生表現の資源を1つも作らない。
    定数近似,
    /// 遠方環境から焼いたLambert拡散照度とGGX鏡面畳込みで答える。
    遠方環境LambertGGX,
}

impl 照明問い合わせ契約 {
    /// 遠方環境と派生表現のGPU資源を作るか。作ると答えるのは遠方環境の契約だけである。
    ///
    /// 遠方環境は大気のベイク済み画像のスカイビューを読んで焼くため、ベイク済み画像を作らないフレーム構成では
    /// 焼ける元が無い。その組み合わせは型付きの失敗にし、定数近似へは戻さない。
    pub(crate) fn 遠方環境の資源を作るか(self, 大気のベイク済み画像あり: bool) -> Result<bool, 空エラー> {
        match (self, 大気のベイク済み画像あり) {
            (Self::定数近似, _) => Ok(false),
            (Self::遠方環境LambertGGX, true) => Ok(true),
            (Self::遠方環境LambertGGX, false) => Err(空エラー::遠方環境の元になる大気がない),
        }
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn 定数近似は大気の有無によらず遠方環境の資源を作らない() {
        assert!(!照明問い合わせ契約::定数近似.遠方環境の資源を作るか(true).unwrap());
        assert!(!照明問い合わせ契約::定数近似.遠方環境の資源を作るか(false).unwrap());
    }

    #[test]
    fn 遠方環境の契約は大気があるときだけ資源を作る() {
        assert!(照明問い合わせ契約::遠方環境LambertGGX.遠方環境の資源を作るか(true).unwrap());
    }

    #[test]
    fn 遠方環境の契約で大気が無ければ型付きの失敗になる() {
        let 誤り = 照明問い合わせ契約::遠方環境LambertGGX.遠方環境の資源を作るか(false);
        assert!(matches!(誤り, Err(空エラー::遠方環境の元になる大気がない)));
    }
}
