//! 拡散の間接光の色を求める工程。受け取るのは拡散照度の立方体画像が返した照度とベースカラーと反射率と金属度、
//! 返すのは表面が返す拡散の色である。触れる状態を持たない。
//!
//! 取り分に`(1-反射率)`を掛けるのは、鏡面へ跳ね返った光が表面の内側へ入らないためである。さらに`(1-金属度)`を
//! 掛けるのは、金属が透過した光をその場で吸収して拡散として戻さないためである。この2つを掛けないと、
//! 直接光の側が守っているエネルギー保存が間接光だけで破れ、金属が拡散の色ぶんだけ明るくなる
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」)。
//!
//! 拡散照度の画像が保つのはLambertの畳み込み後の照度そのものであり、円周率で割るのは消費側の役目である。
//!
//! 注意: この式は`shaders/distant_environment_shading.slang`の写しを持つ。ここが正本である。

/// 拡散が受け取るエネルギーの取り分。
pub fn 拡散の取り分を求める(反射率: [f64; 3], 金属度: f64) -> [f64; 3] {
    let 金属でない割合 = 1.0 - 金属度.clamp(0.0, 1.0);
    [
        (1.0 - 反射率[0]) * 金属でない割合,
        (1.0 - 反射率[1]) * 金属でない割合,
        (1.0 - 反射率[2]) * 金属でない割合,
    ]
}

/// 拡散の間接光の色。取り分と照度とベースカラーを掛け、Lambertの規約どおり円周率で割る。
pub fn 間接拡散の色を求める(取り分: [f64; 3], 照度: [f64; 3], ベースカラー: [f64; 3]) -> [f64; 3] {
    let 成分 = |添字: usize| 取り分[添字] * 照度[添字] * ベースカラー[添字] / std::f64::consts::PI;
    [成分(0), 成分(1), 成分(2)]
}
