//! 鏡面の間接光の色を求める工程と、粗さから鏡面畳込みの縮小段の位置を求める工程。受け取るのは畳み込み後の
//! 放射輝度と垂直入射の反射率と反射率積分表の2成分、または粗さと段数であり、返すのは色または段の位置である。
//!
//! 分割和の第2項を`垂直入射の反射率×第1成分+第2成分`の形で適用するのは、反射率積分表がその形で焼かれて
//! いるためである(`derived/brdf_integration.rs`)。表の軸は法線と視線の余弦と粗さであり、材質の色を含まない。
//!
//! 粗さから段の位置を線形に取るのは、鏡面畳込みが段の粗さを`段番号/(段数-1)`で焼いているためである
//! (`derived/specular_resolution.rs`の`段の粗さ`)。焼く側の対応と参照する側の対応が逆写像でなければ、
//! 粗さ0.5の表面が粗さ0.4で焼いた段を参照する。
//!
//! 注意: この式は`shaders/distant_environment_shading.slang`の写しを持つ。ここが正本である。

use super::super::derived::鏡面畳込みの解像度;

/// 鏡面の間接光の色。
pub fn 間接鏡面の色を求める(
    畳み込みの放射輝度: [f64; 3], 垂直入射の反射率: [f64; 3], 表の2成分: [f64; 2]
) -> [f64; 3] {
    let 成分 = |添字: usize| 畳み込みの放射輝度[添字] * (垂直入射の反射率[添字] * 表の2成分[0] + 表の2成分[1]);
    [成分(0), 成分(1), 成分(2)]
}

/// 粗さが指す縮小段の位置。整数へ丸めず実数で返すのは、GPUが段の間を補間して標本するためである。
/// 段の数は焼いた解像度が答えるため、参照する側が段数を別に持たない。
pub fn 粗さから縮小段の位置を求める(粗さ: f64, 解像度: 鏡面畳込みの解像度) -> f64 {
    let 最も粗い段の番号 = f64::from(解像度.粗さ段数() - 1);
    粗さ.clamp(0.0, 1.0) * 最も粗い段の番号
}
