//! 消費式の性質の反証。GPUを1つも使わず、金属と誘電体でエネルギーの分かれ方が変わることと、
//! 粗さと縮小段の対応が焼く側の逆写像であることを見る。

use super::super::derived::鏡面畳込みの解像度;
use super::*;

const 許容: f64 = 1.0e-12;

fn 近いか(左: f64, 右: f64) -> bool {
    (左 - 右).abs() <= 許容
}

#[test]
fn 金属の垂直入射の反射率はベースカラーそのものである() {
    let 反射率 = 垂直入射の反射率を求める([0.9, 0.6, 0.3], 1.0);
    assert!(近いか(反射率[0], 0.9) && 近いか(反射率[1], 0.6) && 近いか(反射率[2], 0.3));
}

#[test]
fn 誘電体の垂直入射の反射率は基準の値である() {
    let 反射率 = 垂直入射の反射率を求める([0.9, 0.6, 0.3], 0.0);
    assert!(反射率.iter().all(|成分| 近いか(*成分, 誘電体の基準反射率)));
}

#[test]
fn 金属の拡散の取り分は0である() {
    let 反射率 = 粗さ対応の反射率を求める(0.5, 垂直入射の反射率を求める([0.9, 0.6, 0.3], 1.0), 0.4);
    let 取り分 = 拡散の取り分を求める(反射率, 1.0);
    assert!(取り分.iter().all(|成分| 近いか(*成分, 0.0)));
}

#[test]
fn 誘電体の拡散の取り分は反射した残りである() {
    let 反射率 = [0.04, 0.04, 0.04];
    let 取り分 = 拡散の取り分を求める(反射率, 0.0);
    assert!(取り分.iter().all(|成分| 近いか(*成分, 0.96)));
}

#[test]
fn 拡散の色は円周率で割った積である() {
    let 色 = 間接拡散の色を求める([0.5, 0.5, 0.5], [2.0, 4.0, 8.0], [0.2, 0.4, 0.8]);
    let 期待 = |照度: f64, ベースカラー: f64| 0.5 * 照度 * ベースカラー / std::f64::consts::PI;
    assert!(近いか(色[0], 期待(2.0, 0.2)) && 近いか(色[1], 期待(4.0, 0.4)) && 近いか(色[2], 期待(8.0, 0.8)));
}

#[test]
fn 正面から見た粗さ対応の反射率は垂直入射の反射率そのものである() {
    let 垂直 = [0.04, 0.5, 0.9];
    let 反射率 = 粗さ対応の反射率を求める(1.0, 垂直, 0.3);
    assert!((0..3).all(|添字| 近いか(反射率[添字], 垂直[添字])));
}

#[test]
fn 端から見た粗さ対応の反射率の上限は粗いほど低い() {
    let 垂直 = [0.04, 0.04, 0.04];
    let 滑らか = 粗さ対応の反射率を求める(0.0, 垂直, 0.0);
    let 粗い = 粗さ対応の反射率を求める(0.0, 垂直, 0.5);
    assert!(近いか(滑らか[0], 1.0));
    assert!(粗い[0] < 滑らか[0]);
}

#[test]
fn 鏡面の色は表の2成分を反射率へ適用した積である() {
    let 色 = 間接鏡面の色を求める([1.0, 2.0, 4.0], [0.04, 0.5, 0.9], [0.8, 0.1]);
    assert!(近いか(色[0], 1.0 * (0.04 * 0.8 + 0.1)));
    assert!(近いか(色[1], 2.0 * (0.5 * 0.8 + 0.1)));
    assert!(近いか(色[2], 4.0 * (0.9 * 0.8 + 0.1)));
}

/// 焼く側の段の粗さが単精度で表されるため、往復の許容は単精度の刻みに合わせる。
const 単精度の往復の許容: f64 = 1.0e-6;

#[test]
fn 段の粗さを与えると元の段番号が返る() {
    let 解像度 = 鏡面畳込みの解像度::既定値();
    for 段 in 解像度.全段() {
        let 粗さ = f64::from(解像度.段の粗さ(段).値());
        let 位置 = 粗さから縮小段の位置を求める(粗さ, 解像度);
        let 差 = (位置 - f64::from(段.番号())).abs();
        assert!(差 <= 単精度の往復の許容, "段{}の往復が一致しない: {位置}", 段.番号());
    }
}

#[test]
fn 粗さ1の位置は最も粗い段である() {
    let 解像度 = 鏡面畳込みの解像度::既定値();
    let 位置 = 粗さから縮小段の位置を求める(1.0, 解像度);
    assert!(近いか(位置, f64::from(解像度.粗さ段数() - 1)));
}
