//! 間接光が表面で跳ね返る割合を求める工程。受け取るのはベースカラーと金属度、または法線と視線の余弦と粗さ、
//! 返すのは3成分の反射率である。触れる状態を持たない。
//!
//! 直接光のフレネルと式が違うのは、参照する角度が違うためである。直接光は光の向きと視線の中間の向きを持つが、
//! 間接光は半球全体から来るためその中間の向きが1本に定まらず、法線と視線の余弦で代用する。そのうえで
//! 粗い表面は端で反射率が上がりきらないため、上限を粗さで下げる(Sebastien Lagardeの粗さ対応Schlick)。
//! 上限を下げないと、粗い金属の輪郭が実際より明るく縁取られる。
//!
//! 注意: この式は`shaders/distant_environment_shading.slang`の写しを持つ。ここが正本である。

/// 誘電体(金属でない材質)の垂直入射の反射率。
/// 注意: `shaders/distant_environment_shading.slang`の`dielectricBaseReflectance`と一致させる
/// (`cargo xtask conform`が検査する)。直接光側の`shaders/pbr.slang`も同じ値を使う。
pub const 誘電体の基準反射率: f64 = 0.04;

/// 垂直入射の反射率。誘電体の基準反射率とベースカラーを金属度で混ぜる。金属は自分の色で反射し、
/// 誘電体は色を持たない一定の割合で反射する。
pub fn 垂直入射の反射率を求める(ベースカラー: [f64; 3], 金属度: f64) -> [f64; 3] {
    let 混ぜる = |色: f64| 誘電体の基準反射率 + (色 - 誘電体の基準反射率) * 金属度;
    [混ぜる(ベースカラー[0]), 混ぜる(ベースカラー[1]), 混ぜる(ベースカラー[2])]
}

/// 粗さ対応の反射率。余弦が0へ近づくほど上限へ寄り、その上限は粗い表面ほど低い。
pub fn 粗さ対応の反射率を求める(法線と視線の余弦: f64, 垂直入射の反射率: [f64; 3], 粗さ: f64) -> [f64; 3] {
    let 減り = (1.0 - 法線と視線の余弦.clamp(0.0, 1.0)).powi(5);
    let 上限 = 1.0 - 粗さ.clamp(0.0, 1.0);
    let 成分 = |反射率: f64| 反射率 + (上限.max(反射率) - 反射率) * 減り;
    [成分(垂直入射の反射率[0]), 成分(垂直入射の反射率[1]), 成分(垂直入射の反射率[2])]
}
