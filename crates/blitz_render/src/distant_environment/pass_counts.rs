//! 1フレームで積んだ、間接照明の表現を焼くパスの本数の内訳。
//!
//! 大気のベイク済み画像の生成パス数と別の型にするのは、既存の計数の意味を変えないためである。大気の本数は
//! 「大気の表を何枚焼いたか」を表す判定値として検収が読んでおり、そこへ遠方環境の本数を足すと既存の判定値が動く。
//!
//! 内訳を1つの合計に潰さないのは、期待する本数がパスごとに違うためである。遠方環境と拡散照度は焼くフレームに1本、
//! 鏡面畳込みは計算で焼く段の数だけ、反射率積分表は起動後の1回だけであり、合計だけでは段の数え違いを見分けられない。

/// パスの種類ごとの本数。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 間接照明生成パス数 {
    pub 遠方環境: u32,
    /// 鏡面畳込みの最詳細段を遠方環境から複製する転送パス。計算では焼かないため計算のパスと分けて数える。
    pub 最詳細段の複製: u32,
    pub 拡散照度: u32,
    /// 鏡面畳込みを計算で焼くパス。最詳細段は複製で作るため、粗さ段数から1を引いた本数になる。
    pub 鏡面畳込み: u32,
    pub 反射率積分表: u32,
}

impl 間接照明生成パス数 {
    /// 1本も積まないフレームの内訳。
    pub fn 焼かない() -> Self {
        Self::default()
    }

    /// 遠方環境を焼き直したフレームの内訳。遠方環境と最詳細段の複製と拡散照度がそれぞれ1本、鏡面畳込みが
    /// 計算で焼いた段の数、反射率積分表がまだ焼いていなかったときだけ1本である。
    pub fn 焼いたフレーム(計算で焼いた鏡面の段数: u32, 反射率積分表を焼いたか: bool) -> Self {
        Self {
            遠方環境: 1,
            最詳細段の複製: 1,
            拡散照度: 1,
            鏡面畳込み: 計算で焼いた鏡面の段数,
            反射率積分表: u32::from(反射率積分表を焼いたか),
        }
    }

    pub fn 合計(self) -> u32 {
        self.遠方環境 + self.最詳細段の複製 + self.拡散照度 + self.鏡面畳込み + self.反射率積分表
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 焼かないフレームは全部0で合計も0() {
        let 本数 = 間接照明生成パス数::焼かない();
        assert_eq!(本数.遠方環境, 0);
        assert_eq!(本数.最詳細段の複製, 0);
        assert_eq!(本数.拡散照度, 0);
        assert_eq!(本数.鏡面畳込み, 0);
        assert_eq!(本数.反射率積分表, 0);
        assert_eq!(本数.合計(), 0);
    }

    /// 既定の鏡面畳込みは6段であり、最詳細段は複製で作るため計算で焼くのは5段である。
    const 計算で焼く段数: u32 = 5;

    #[test]
    fn 初回に焼くフレームは遠方環境と複製と拡散が各1本で鏡面が段数ぶん反射率が1本() {
        let 本数 = 間接照明生成パス数::焼いたフレーム(計算で焼く段数, true);
        assert_eq!(本数.遠方環境, 1);
        assert_eq!(本数.最詳細段の複製, 1);
        assert_eq!(本数.拡散照度, 1);
        assert_eq!(本数.鏡面畳込み, 計算で焼く段数);
        assert_eq!(本数.反射率積分表, 1);
        assert_eq!(本数.合計(), 3 + 計算で焼く段数 + 1);
    }

    #[test]
    fn 二回目以降の焼き直しは反射率積分表を焼かない() {
        let 本数 = 間接照明生成パス数::焼いたフレーム(計算で焼く段数, false);
        assert_eq!(本数.反射率積分表, 0);
        assert_eq!(本数.合計(), 3 + 計算で焼く段数);
    }
}
