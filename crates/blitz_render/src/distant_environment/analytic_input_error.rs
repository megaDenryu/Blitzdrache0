//! 検収が注入する解析入力が受け付けられないときの失敗。値そのものの不正と、焼いた資源との噛み合わない指定を1つの型で表す。
//!
//! 1フレーム入力の不一致と別に持つのは、生存期間が違うためである。この失敗は起動直後の注入の1回だけで決まり、
//! フレームごとに評価されない。

use thiserror::Error;

#[derive(Debug, Clone, Copy, Error, PartialEq, Eq)]
pub enum 遠方環境の解析入力エラー {
    #[error("解析入力の値は有限かつ0以上でなければならない")]
    値域外,

    #[error("鏡面畳込みの段ごとの色が{与えた}件だが、焼いた画像の粗さ段は{求める}段である")]
    段数不一致 { 求める: u32, 与えた: usize },

    #[error("遠方環境の解析入力が2度注入された")]
    二重注入, // 2度目の注入。1度目のバッファを破棄せずに置き換えると、以降の転送元がどちらの中身かを型から決められない

    #[error("照明問い合わせ契約が遠方環境の枝でないため注入する先が無い")]
    遠方環境の資源なし, // 照明問い合わせ契約が定数近似の実行。派生表現の画像そのものが無いため、注入する先が1つも無い
}
