//! 遠方環境をそのフレームで焼き直すかどうかの指示。
//!
//! 焼き直すかどうかを上位層が決めるのは、判定に使う遠方環境キーが方針の全パラメータを並べた完全比較キーであり、
//! それを持つのが方針を保持する層だからである。`blitz_render`は上位のエンジン層へ依存しないため鍵そのものを
//! 受け取れず、鍵から導いた指示だけが境界を越える(大気のベイク済み画像の生成指示と同じ形)。
//!
//! 明るさの尺度と観測条件をこの型が持たないのは、どちらも別の正本があるためである。尺度は空描画方針、
//! 観測半径と太陽の天頂余弦は大気のベイク済み画像の入力のスカイビュー観測条件が正本であり、
//! 同じ値を2箇所で持つと焼いた条件と参照する条件が食い違いうる。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「鍵の設計(2つの注意)」

/// そのフレームで遠方環境を焼き直すか。枝が2つしかないのは、遠方環境が1枚の画像であり、
/// 部分的に焼き直すという状態を持たないためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 遠方環境の生成指示 {
    前の結果を使う, // 遠方環境キーが前フレームと同じである。生成パスを1本も積まない。
    焼き直す,       // 遠方環境キーが変わった、またはまだ1度も焼いていない。6面すべてを焼き直す。
}
