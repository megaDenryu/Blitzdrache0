//! 検収が遠方環境の立方体画像へ与える値。担うのは「焼き上げの入力そのものを置き換えたときに、生成側が何から
//! 焼くか」を宣言することだけであり、Vulkanの資源もバイト並びも知らない。
//!
//! 派生表現へ直に与える解析入力と別の型にするのは、確かめる対象が違うためである。あちらは生成側を止めて消費式だけを
//! 見るのに対し、こちらは生成側を働かせ「定数の遠方環境から焼いた拡散照度と鏡面畳込みを、消費側が正しく読むか」を見る。
//! 定数の放射輝度`L`を与えると拡散照度は円周率×`L`・鏡面畳込みはどの粗さ段も`L`になるため、消費まで閉じた形の答えが残る。
//!
//! 反射率積分表だけを一緒に与えるのは、その表が遠方環境に依らず、消費の期待値へ掛かる係数としてしか効かないためである。
//! 焼いた表を使うと、期待値の側が表の標本の補間まで再現しなければならなくなり、確かめたい連なりに関係のない誤差が混ざる。
//! 表そのものの正しさは`cargo xtask derived-environment`が別に見ている。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」

use super::analytic_input_error::遠方環境の解析入力エラー;

/// 遠方環境の立方体画像へ与える一様な放射輝度と、一緒に与える反射率積分表の2成分。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 遠方環境の焼かせる解析入力 {
    一様な放射輝度: [f32; 3],
    反射率積分表: [f32; 2],
}

impl 遠方環境の焼かせる解析入力 {
    pub fn 生成する(一様な放射輝度: [f32; 3], 反射率積分表: [f32; 2]) -> Result<Self, 遠方環境の解析入力エラー> {
        let 妥当 = 有限で非負か(&一様な放射輝度) && 有限で非負か(&反射率積分表);
        if !妥当 {
            return Err(遠方環境の解析入力エラー::値域外);
        }
        Ok(Self {
            一様な放射輝度,
            反射率積分表,
        })
    }

    /// 遠方環境の全テクセルへ書く放射輝度。太陽相対座標のどの向きも同じ値になる。
    pub fn 一様な放射輝度(&self) -> [f32; 3] {
        self.一様な放射輝度
    }

    pub fn 反射率積分表(&self) -> [f32; 2] {
        self.反射率積分表
    }
}

fn 有限で非負か(値: &[f32]) -> bool {
    値.iter().all(|成分| 成分.is_finite() && *成分 >= 0.0)
}
