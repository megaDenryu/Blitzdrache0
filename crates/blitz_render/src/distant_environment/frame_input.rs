//! 遠方環境と派生表現の1フレーム入力。焼き直すかどうかの指示と、焼く内容を決める明るさの尺度を1つに束ねる。
//!
//! 尺度をこの型が運ぶのは、太陽放射照度と夜空放射輝度が空描画方針から来る値であり、大気のベイク済み画像の入力が
//! 持つ観測条件とは出どころが違うためである。観測半径と太陽の天頂余弦をここへ持たないのは、それらの正本が
//! 大気のベイク済み画像の入力のスカイビュー観測条件だからであり、同じ値を2箇所で持つと焼いた条件と参照する条件が
//! 食い違いうる(参照: `_doc/設計/放射輝度問い合わせ階層.md`「鍵の設計(2つの注意)」)。

use super::input::遠方環境の生成指示;
use crate::atmosphere::天空放射輝度の尺度;

/// 照明問い合わせ契約が遠方環境の枝である世界のフレームが毎フレーム渡す入力。
#[derive(Debug, Clone, Copy)]
pub struct 遠方環境の入力 {
    尺度: 天空放射輝度の尺度,
    生成指示: 遠方環境の生成指示,
}

impl 遠方環境の入力 {
    pub fn 生成する(尺度: 天空放射輝度の尺度, 生成指示: 遠方環境の生成指示) -> Self {
        Self { 尺度, 生成指示 }
    }

    pub(crate) fn 尺度(&self) -> 天空放射輝度の尺度 {
        self.尺度
    }

    pub(crate) fn 生成指示(&self) -> 遠方環境の生成指示 {
        self.生成指示
    }
}
