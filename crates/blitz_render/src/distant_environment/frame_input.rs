//! 遠方環境と派生表現の1フレーム入力。焼き直すかどうかの指示と、焼く内容を決める明るさの尺度を1つに束ねる。
//!
//! 尺度をこの型が運ぶのは、太陽放射照度と夜空放射輝度が空描画方針から来る値であり、大気のベイク済み画像の入力が
//! 持つ観測条件とは出どころが違うためである。
//!
//! 観測条件を大気の入力から借りずにこの型が持つのは、遠方環境の焼く入力だけが太陽の天頂余弦を代表天頂余弦へ
//! 正規化するためである。大気の入力が持つのは時計の進行で毎フレーム動く連続な条件であり、そちらを読むと
//! 間引きが効かない(参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」)。
//! この条件は遠方環境用スカイビューを焼く条件でもあり、遠方環境の焼き上げが参照する条件でもある。

use super::input::遠方環境の生成指示;
use super::sun_direction::ワールドの太陽方向;
use crate::atmosphere::{スカイビュー観測条件, 天空放射輝度の尺度};

/// 照明問い合わせ契約が遠方環境の枝である世界のフレームが毎フレーム渡す入力。
#[derive(Debug, Clone, Copy)]
pub struct 遠方環境の入力 {
    尺度: 天空放射輝度の尺度,
    太陽方向: ワールドの太陽方向,
    スカイビュー条件: スカイビュー観測条件,
    生成指示: 遠方環境の生成指示,
}

impl 遠方環境の入力 {
    pub fn 生成する(
        尺度: 天空放射輝度の尺度,
        太陽方向: ワールドの太陽方向,
        スカイビュー条件: スカイビュー観測条件,
        生成指示: 遠方環境の生成指示,
    ) -> Self {
        Self {
            尺度,
            太陽方向,
            スカイビュー条件,
            生成指示,
        }
    }

    /// 代表天頂余弦で作った観測条件。遠方環境用スカイビューの焼き上げと遠方環境の焼き上げが同じ1つを読む。
    pub(crate) fn スカイビュー条件(&self) -> スカイビュー観測条件 {
        self.スカイビュー条件
    }

    pub(crate) fn 尺度(&self) -> 天空放射輝度の尺度 {
        self.尺度
    }

    /// 表面が法線と反射方向を太陽相対座標へ写すための向き。焼く条件には入らない。
    pub(crate) fn 太陽方向(&self) -> ワールドの太陽方向 {
        self.太陽方向
    }

    pub(crate) fn 生成指示(&self) -> 遠方環境の生成指示 {
        self.生成指示
    }
}
