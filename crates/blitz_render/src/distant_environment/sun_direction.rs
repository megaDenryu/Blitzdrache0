//! ワールド軸で表した太陽の向き。受け取るのは3成分、返すのは長さ1へそろえた向きである。触れる状態を持たない。
//!
//! 遠方環境は太陽相対座標で焼くため、表面が拡散照度と鏡面畳込みを参照するには法線と反射方向を同じ座標へ写す
//! 必要がある。その写しに要る唯一の外部入力がこの向きであり、GPUへは照明問い合わせヘッダが運ぶ
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「鍵の設計(2つの注意)」)。
//!
//! 焼く条件を決める`天空放射輝度の尺度`と別に持つのは、この向きが焼いた内容を1つも変えないためである。
//! 太陽の方位だけが動いても遠方環境は焼き直さず、参照する側の座標の回し方だけが変わる。

use crate::atmosphere::大気数学エラー;

/// 地表から太陽へ向かう単位ベクトル。ワールド軸はXが東、Yが天頂、Zが南である。
/// 不変条件: 3成分は有限であり、長さが1である(生成時に正規化する)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ワールドの太陽方向 {
    成分: [f32; 3],
}

impl ワールドの太陽方向 {
    pub fn 生成する(東: f32, 天頂: f32, 南: f32) -> Result<Self, 大気数学エラー> {
        let 成分 = [東, 天頂, 南];
        let 長さ二乗: f32 = 成分.iter().map(|値| 値 * 値).sum();
        if !長さ二乗.is_finite() || 長さ二乗 <= f32::EPSILON {
            return Err(大気数学エラー::値域外 {
                項目: "ワールドの太陽方向の長さ二乗",
                値: 長さ二乗,
            });
        }
        let 逆長さ = 長さ二乗.sqrt().recip();
        Ok(Self {
            成分: 成分.map(|値| 値 * 逆長さ),
        })
    }

    pub fn 成分(&self) -> [f32; 3] {
        self.成分
    }
}
