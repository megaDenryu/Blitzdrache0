//! 遠方環境の派生表現のGPU読み戻し検査の公開入口。担当するのは「与えた遠方環境の上に拡散照度・鏡面畳込み・
//! 反射率積分表を本番と同じパス宣言で焼き、4つの画像の中身を生の成分で返す」ことである。
//! 呼び出し元は検収コマンドだけであり、本番の描画経路はここを通らない。
//!
//! 検証済みの値オブジェクトでなく生の成分を返すのは、検査が非有限値や負の値を観測できなければならないためである。
//! 検証済みの型で返すと、まさに検査したい壊れた値が構築の時点で弾かれ、GPU側の欠陥が見えなくなる。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「検収(機械判定)」

use crate::compute_shader::コンピュートシェーダー;
use crate::distant_environment::derived::{
    反射率積分表の解像度, 拡散照度の解像度, 遠方環境の内容, 鏡面畳込みの解像度
};
use crate::error::レンダラーエラー;
use crate::validation_counter::検証層の状況;
use crate::vulkan::derived_environment;

/// 焼く条件一式。引数の列が伸び続けるのを避けて1つに束ねる。
pub struct 派生表現の焼き上げ条件<'a> {
    pub 遠方環境: &'a 遠方環境の内容,
    pub 拡散照度の解像度: 拡散照度の解像度,
    pub 鏡面畳込みの解像度: 鏡面畳込みの解像度,
    pub 反射率積分表の解像度: 反射率積分表の解像度,
    pub 拡散照度のシェーダー: &'a コンピュートシェーダー,
    pub 鏡面畳込みのシェーダー: &'a コンピュートシェーダー,
    pub 反射率積分表のシェーダー: &'a コンピュートシェーダー,
}

/// GPUが焼いた4つの画像の中身と、その実行のvalidationの観測。
///
/// 立方体の3つは並びが面(層番号の順)・縦・横の順であり、鏡面畳込みはさらに段が最も外側に来る。
/// 反射率積分表は縦が外、横が速い。立方体の4成分目はシェーダーが予約として0を書くため、読む側はRGBの3成分だけを見る。
pub struct 派生表現の読み戻し {
    遠方環境: Vec<[f32; 4]>,
    拡散照度: Vec<[f32; 4]>,
    鏡面畳込み: Vec<[f32; 4]>,
    反射率積分表: Vec<[f32; 2]>,
    検証層の状況: 検証層の状況,
    検証件数: u64,
}

impl 派生表現の読み戻し {
    /// 与えた遠方環境がGPUの画像に載った後の値。派生表現の入力そのものであり、最詳細段との一致の相手になる。
    pub fn 遠方環境(&self) -> &[[f32; 4]] {
        &self.遠方環境
    }

    pub fn 拡散照度(&self) -> &[[f32; 4]] {
        &self.拡散照度
    }

    pub fn 鏡面畳込み(&self) -> &[[f32; 4]] {
        &self.鏡面畳込み
    }

    pub fn 反射率積分表(&self) -> &[[f32; 2]] {
        &self.反射率積分表
    }

    /// validation層を有効にできたかどうか。件数0が保証になるのは有効だった実行だけである。
    pub fn 検証層の状況(&self) -> 検証層の状況 {
        self.検証層の状況
    }

    pub fn 検証件数(&self) -> u64 {
        self.検証件数
    }
}

/// ウィンドウもスワップチェーンも作らずにGPUを初期化し、本番と同じパス宣言で3つの派生表現を焼いて読み戻す。
/// 送信は1回で、戻った時点でGPUの作業は完了している。
pub fn 派生表現をgpuで焼いて読み戻す(
    条件: 派生表現の焼き上げ条件<'_>
) -> Result<派生表現の読み戻し, レンダラーエラー> {
    let (読み戻し, 検証) = derived_environment::派生表現をgpuで焼いて読み戻す(derived_environment::派生表現を焼く条件 {
        遠方環境: 条件.遠方環境,
        拡散照度の解像度: 条件.拡散照度の解像度,
        鏡面畳込みの解像度: 条件.鏡面畳込みの解像度,
        反射率積分表の解像度: 条件.反射率積分表の解像度,
        拡散照度のシェーダー: 条件.拡散照度のシェーダー,
        鏡面畳込みのシェーダー: 条件.鏡面畳込みのシェーダー,
        反射率積分表のシェーダー: 条件.反射率積分表のシェーダー,
    })?;
    Ok(派生表現の読み戻し {
        遠方環境: 読み戻し.遠方環境,
        拡散照度: 読み戻し.拡散照度,
        鏡面畳込み: 読み戻し.鏡面畳込み,
        反射率積分表: 読み戻し.反射率積分表,
        検証層の状況: 検証.状況,
        検証件数: 検証.件数,
    })
}
