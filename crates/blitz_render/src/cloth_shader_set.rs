//! 布シミュレーションのシェーダー束(判断54)。コンピュート10本と、シーンパス・シャドウパスの描画2組。
//! 各フィールドの検証は`コンピュートシェーダー`/`シェーダー一式`の生成時に済んでいる。

use crate::compute_shader::コンピュートシェーダー;
use crate::indirect_lighting::契約別の描画シェーダー;
use crate::shader_set::シェーダー一式;

/// `乗数零化`は物理刻みの開始でラグランジュ乗数を零へ戻し、`拘束`は色ごとに1回積まれて正典式で位置と乗数を直接書く。
/// `描画`はシーンパスで布を描くもので、画素段は照明問い合わせ契約ごとに分かれ、頂点段は両方が同じものを持つ。
/// `シャドウ`は個体変換も可視ID列も読まないため、布の影は描画対象の走査順に依らない。
#[derive(Debug, Clone)]
pub struct 布シェーダー一式 {
    pub 介入: コンピュートシェーダー,
    pub 積分: コンピュートシェーダー,
    pub アタッチ: コンピュートシェーダー,
    pub 乗数零化: コンピュートシェーダー,
    pub 拘束: コンピュートシェーダー,
    pub ハッシュ消去: コンピュートシェーダー,
    pub ハッシュ格納: コンピュートシェーダー,
    pub 分離: コンピュートシェーダー,
    pub 仕上げ: コンピュートシェーダー,
    pub 頂点生成: コンピュートシェーダー,
    pub 描画: 契約別の描画シェーダー, // シーンパスで布を描く
    pub シャドウ: シェーダー一式,     // シャドウパスで布だけを描く専用のもの
}
