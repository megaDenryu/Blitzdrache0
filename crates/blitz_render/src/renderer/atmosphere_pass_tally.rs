//! 大気LUT生成パスの実行数の記録。担当するのは「フレームごとにレンダーグラフへ積まれた生成パスの本数を数え、
//! 先頭の数フレームぶんは1本ずつの列として、それ以降は総数として保つ」ことである。
//!
//! 数える場所をグラフの積み上げ側に置くのは、焼き直しの指示から本数を推し量ると、指示と実際に積まれたパスが
//! 食い違ったときにその食い違いを見逃すためである。数えているのはGPUへ発行される本数そのものである。
//!
//! 先頭のフレームだけ列を持つのは、更新判定の期待(初回は3本・条件が変わらないフレームは0本・太陽だけが動く
//! フレームは1本)がフレームの並びとして現れるためである。長い実行でも記録が伸びないよう上限を置き、
//! 上限より後は総数だけを足す(切り捨てたことは`数えたフレーム数`と列の長さの差で読める)。

/// 1本ずつの列として残す先頭フレーム数。検収の実行が数十フレーム規模であるため、その全体を覆う長さを採る。
const 列の上限: usize = 256;

#[derive(Debug, Clone, Default)]
pub struct 大気LUT生成パス数の記録 {
    先頭フレームの列: Vec<u32>,
    数えたフレーム数: u64,
    生成パスの総数: u64,
}

impl 大気LUT生成パス数の記録 {
    pub(crate) fn 新規() -> Self {
        Self {
            先頭フレームの列: Vec::with_capacity(列の上限),
            数えたフレーム数: 0,
            生成パスの総数: 0,
        }
    }

    /// 1フレームぶんの本数を記録する。呼ぶのはコマンド記録を終えたフレームだけである。
    pub(crate) fn 記録する(&mut self, 本数: u32) {
        if self.先頭フレームの列.len() < 列の上限 {
            self.先頭フレームの列.push(本数);
        }
        self.数えたフレーム数 += 1;
        self.生成パスの総数 += u64::from(本数);
    }

    /// 先頭から順に並べた、フレームごとの生成パス本数。長さは`列の上限`で頭打ちになる。
    pub fn 先頭フレームの列(&self) -> &[u32] {
        &self.先頭フレームの列
    }

    pub fn 数えたフレーム数(&self) -> u64 {
        self.数えたフレーム数
    }

    pub fn 生成パスの総数(&self) -> u64 {
        self.生成パスの総数
    }
}
