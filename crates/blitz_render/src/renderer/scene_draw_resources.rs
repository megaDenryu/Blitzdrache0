//! 描画対象の個数に連動するGPU資源の束: 呼び出し元が単位として扱う束の集合・毎フレームの描画入力作業領域・解除予約された束の待機列。
//! 作業領域はシーン1本と距離区分ごとに1本であり、毎フレーム空にしてから束一覧を先頭から走査して積み直す。
//! ディスクリプタセット添字は束の内側で閉じるため、ある束の追加・解除が他の束の添字をずらさない。
//! セットレイアウトと、描画対象で変わらないset0・set3のセットは束の外(レンダラー直下)が所有する(参照: `vulkan::descriptor`)。
//! 生成は`create`、束1つぶんの資源は`chunk_draw_resources`、束の追加と解除は`bundle_lifecycle`、毎フレームの作業領域更新は`work_area`、描画対象1つぶんの資源は`render_object_resources`にある。
//! `距離区分別のシャドウ入力作業領域`が1本の列を4距離区分で共有できないのは、距離区分別の可視個体の選別では距離区分ごとに描く個体が違うためである。
//! `点光源の影の作業領域`が面の数だけ列を持たないのは、面ごとの絞りを記録の地点が球の判定で行うためである(参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断n」)。
//! `破棄待ち`はGPUが使い終わるまでフレームを数えてから破棄する(規律は`bundle_lifecycle`が持つ)。
//! `実破棄済みid一覧`は呼び出し元が引き取るまで貯まる。解除の予約と実破棄は時点が違い、資源の会計は実破棄の時点でしか減らせないため、破棄の事実をIDで外へ返す。
//! `計数集計`が内訳の値そのものでなく集計の状態を持つのは、候補数・可視数・段別個体数を充填の途中でしか数えられず、段ごとの列を使い回すためである。
//! `影のキャスター`は作業領域と同じ充填で決まるため、読み出しと食い違わない。

mod bundle_lifecycle;
mod chunk_draw_resources;
mod create;
mod render_object_resources;
mod work_area;

use crate::cascade::距離区分数;
use crate::draw_bundle_id::描画束ID;

use crate::vulkan::frame::{シャドウ描画入力, ジオメトリ入力, 点光源の影の描画発行};
use crate::vulkan::tracked_device::GPUデバイス;
use bundle_lifecycle::破棄待ち束;
use chunk_draw_resources::チャンク描画資源;

pub(in crate::renderer) use create::起動シーンの束ID;
pub(super) use create::{シーン描画資源生成要求, 束追加材料};
pub(super) use work_area::作業領域更新入力;
use work_area::描画計数集計;

pub(super) struct シーン描画資源 {
    チャンク一覧: Vec<チャンク描画資源>,
    ジオメトリ入力作業領域: Vec<ジオメトリ入力>,
    距離区分別のシャドウ入力作業領域: [Vec<シャドウ描画入力>; 距離区分数], // 距離区分ごとのシャドウ描画入力
    点光源の影の作業領域: Vec<点光源の影の描画発行>,                       // 点光源の影の発行。面ごとに描く対象が違っても列は1本である
    破棄待ち: Vec<破棄待ち束>,                                             // 解除を予約された束
    実破棄済みid一覧: Vec<描画束ID>,                                       // 実際にGPU資源を破棄し終えた束のID
    計数集計: 描画計数集計,                                                // 直近に作業領域を充填したときの計数
    影のキャスター: crate::frame_input::影のキャスター指定,                // 直近の充填が前提にしたシャドウのキャスター指定
}

impl シーン描画資源 {
    /// 注意: セットレイアウトを破棄するのは束の外であり、その破棄はここの全束のディスクリプタプールの破棄より後に来る
    /// (レイアウトはプールが割り当てたセットの生存前提である)。
    /// 前提: レンダラー全体の破棄順は renderer/destroy.rs が持ち、この束はその1段として呼ばれる(GPU待機済み)。
    pub(super) fn 破棄する(&self, device: &GPUデバイス) {
        for 待ち in &self.破棄待ち {
            待ち.束().破棄する(device);
        }
        for チャンク in &self.チャンク一覧 {
            チャンク.破棄する(device);
        }
    }
}
