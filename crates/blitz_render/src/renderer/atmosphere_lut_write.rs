//! 大気のベイク済み画像の入力を受け取る工程。担当するのは「そのフレームの大気入力が大気のベイク済み画像資源の有無と一致することを確かめ、
//! 媒体をベイク済み画像生成と空パスが読むシェーダー定数へ書く」ことである。
//!
//! 焼かないフレームでも書くのは、シェーダー定数がフレームスロットごとに別のバッファであり、そのスロットでまだ
//! 1度も書いていない可能性があるうえ、大気のベイク済み画像方式の空パスが焼かないフレームでも同じシェーダー定数から
//! 惑星半径を読むためである。書く量は媒体1つぶん(数百バイト)であり、条件で分けるより不変条件を1つに保つ方を採る。
//!
//! 不変条件: 大気のベイク済み画像資源の有無とフレーム描画入力の大気媒体の有無は常に一致する。不一致は型付きエラーにする。
//! 無言で既定の大気を使うことも、無言でベイク済み画像を作らないこともしない(参照: CLAUDE.md「不在・未設定・使用不可」)。

use super::レンダラー;
use crate::atmosphere_lut_input::大気のベイク済み画像の生成指示;
use crate::error::{レンダラーエラー, 空エラー};
use crate::frame_input::フレーム描画入力;
use crate::vulkan::atmosphere_lut::大気のベイク済み画像の描画入力;
use crate::vulkan::sync::フレームスロット添字;

impl レンダラー {
    /// 前提: 呼び出し元はこのスロットのフェンス待機を済ませている(`draw_execute/prepare.rs`)。
    pub(super) fn 大気媒体を書き込む(
        &self,
        フレーム添字: フレームスロット添字,
        入力: &フレーム描画入力<'_>,
    ) -> Result<(), レンダラーエラー> {
        match (self.描画段階資源.大気のベイク済み画像を作るか(), &入力.大気) {
            (true, Some(大気)) => self.描画段階資源.大気媒体を書き込む(self.gpu環境.device(), フレーム添字, 大気.媒体()),
            (false, None) => Ok(()),
            (true, None) => Err(空エラー::入力不一致("大気のベイク済み画像資源があるフレーム構成なのに大気媒体が未指定".to_string()).into()),
            (false, Some(_)) => Err(空エラー::入力不一致("大気のベイク済み画像資源の無いフレーム構成に大気媒体が指定された".to_string()).into()),
        }
    }

    /// 大気のベイク済み画像の生成パスが束縛する資源。ベイク済み画像を持たない構成では`None`を返す。
    /// 何も焼かないフレームでも`Some`を返すのは、焼く組が「何も焼かない」であることを段の展開側が読み、
    /// パスを1本も積まないためである。
    ///
    /// 前提: この工程はコマンドを記録して送信するフレームでだけ呼ばれる(取得に失敗して見送るフレームはここへ来ない)。
    /// その前提のもとで「まだ1枚も焼いていない」を記録するため、実際に焼いた事実と記録が食い違わない。
    pub(super) fn 大気のベイク済み画像の描画入力を組み立てる(
        &mut self,
        フレーム添字: フレームスロット添字,
        入力: &フレーム描画入力<'_>,
    ) -> Option<大気のベイク済み画像の描画入力> {
        let 大気 = 入力.大気.as_ref()?;
        let 指示 = self.焼き始めの指示へ格上げする(大気.生成指示());
        self.描画段階資源.大気のベイク済み画像の描画入力を作る(
            フレーム添字,
            大気.媒体(),
            (大気.スカイビュー条件(), 大気.空中遠近条件()),
            指示,
        )
    }

    /// まだ1枚も焼いていないうちに「参照するだけ」の指示が来たら、3枚すべてを焼く指示へ格上げする。
    ///
    /// 上位層の指示は方針の鍵の値比較から導かれるため、鍵を記録した後にそのフレームが見送られた場合まで面倒を見られない。
    /// 見送られたフレームの生成パスはGPUへ届かないため、格上げが無いとベイク済み画像は一度も書かれないまま
    /// 「中身を保つ画像」として扱われ、内容が不定のまま空に出る(レイアウトもUNDEFINEDのままGENERALを期待される)。
    fn 焼き始めの指示へ格上げする(
        &mut self, 指示: 大気のベイク済み画像の生成指示
    ) -> 大気のベイク済み画像の生成指示 {
        let 決めた指示 = match (self.大気のベイク済み画像を焼いたか, 指示) {
            (true, 指示) => 指示,
            (false, _) => 大気のベイク済み画像の生成指示::全部焼き直す,
        };
        if 決めた指示 == 大気のベイク済み画像の生成指示::全部焼き直す {
            self.大気のベイク済み画像を焼いたか = true;
        }
        決めた指示
    }
}
