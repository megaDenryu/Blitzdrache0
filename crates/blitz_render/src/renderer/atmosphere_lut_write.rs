//! 大気LUTの入力を受け取る工程。担当するのは「そのフレームの大気媒体が大気LUT資源の有無と一致することを確かめる」ことである。
//! 触れるレンダラーの状態は描画段階資源が大気LUTを持つかどうかだけであり、GPUの資源へは書き込まない。
//!
//! 不変条件: 大気LUT資源の有無とフレーム描画入力の大気媒体の有無は常に一致する。不一致は型付きエラーにする。
//! 無言で既定の大気を使うことも、無言でLUTを作らないこともしない(参照: CLAUDE.md「不在・未設定・使用不可」)。

use super::レンダラー;
use crate::error::{レンダラーエラー, 空エラー};
use crate::frame_input::フレーム描画入力;

impl レンダラー {
    pub(super) fn 大気媒体の一致を確かめる(&self, 入力: &フレーム描画入力<'_>) -> Result<(), レンダラーエラー> {
        match (self.描画段階資源.空を描くか(), &入力.大気媒体) {
            (true, Some(_)) | (false, None) => Ok(()),
            (true, None) => Err(空エラー::入力不一致("大気LUT資源があるフレーム構成なのに大気媒体が未指定".to_string()).into()),
            (false, Some(_)) => Err(空エラー::入力不一致("大気LUT資源の無いフレーム構成に大気媒体が指定された".to_string()).into()),
        }
    }
}
