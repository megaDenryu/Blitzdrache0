//! 大気LUTの入力を受け取る工程。担当するのは「そのフレームの大気媒体が大気LUT資源の有無と一致することを確かめ、
//! 一致していれば媒体をLUT生成用のユニフォームへ書く」ことである。
//!
//! 不変条件: 大気LUT資源の有無とフレーム描画入力の大気媒体の有無は常に一致する。不一致は型付きエラーにする。
//! 無言で既定の大気を使うことも、無言でLUTを作らないこともしない(参照: CLAUDE.md「不在・未設定・使用不可」)。

use super::レンダラー;
use crate::error::{レンダラーエラー, 空エラー};
use crate::frame_input::フレーム描画入力;
use crate::vulkan::atmosphere_lut::大気LUT描画入力;
use crate::vulkan::sync::フレームスロット添字;

impl レンダラー {
    /// 前提: 呼び出し元はこのスロットのフェンス待機を済ませている(`draw_execute/prepare.rs`)。
    pub(super) fn 大気媒体を書き込む(
        &self,
        フレーム添字: フレームスロット添字,
        入力: &フレーム描画入力<'_>,
    ) -> Result<(), レンダラーエラー> {
        match (self.描画段階資源.大気lutを作るか(), &入力.大気媒体) {
            (true, Some(媒体)) => self.描画段階資源.大気媒体を書き込む(self.環境.device(), フレーム添字, 媒体),
            (false, None) => Ok(()),
            (true, None) => Err(空エラー::入力不一致("大気LUT資源があるフレーム構成なのに大気媒体が未指定".to_string()).into()),
            (false, Some(_)) => Err(空エラー::入力不一致("大気LUT資源の無いフレーム構成に大気媒体が指定された".to_string()).into()),
        }
    }

    /// 大気LUTの生成パスが束縛する資源。LUTを持たない構成では`None`を返し、生成パスを1本も積ませない。
    pub(super) fn 大気lut描画入力を組み立てる(
        &self, フレーム添字: フレームスロット添字
    ) -> Option<大気LUT描画入力> {
        self.描画段階資源.大気lut描画入力を作る(フレーム添字)
    }
}
