//! 1フレーム描画の公開エントリ2系(通常描画・読み戻し付き描画)と、その実行本体:
//! 提示状態の判別 → 再構築 → フェンス待機 → UBO書き込み → 取得 → 描画 → 提示。
//! フレームインフライト2のため、フェンス・取得セマフォ・コマンドバッファ・UBOはすべて同じフレームスロットで選ぶ（判断13・判断24）。
//! スロットを進めるかどうかは1フレームの結末だけで決まるため、`フレーム進行`への反映を`フレームを実行する`の1箇所に集める。
//! 公開エントリは受け取った引数を読み戻し要求の真偽へ写して実行本体へ渡すだけで、独立して触る状態を持たない。
//! 別ファイルへ置くと1つの流れを読むのに2ファイルを開かせるため、実行本体と同じファイルに置く。

mod acquire;
mod prepare;
mod submit;

use super::frame_progress::フレーム結末;
use super::presentation::提示状態;
use super::レンダラー;
use crate::draw_result::{描画結果, 見送り理由};
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::readback_result::読み戻し結果;

impl レンダラー {
    /// 1フレーム分の描画を行い、可能ならスワップチェーンへ提示する。
    pub fn 一フレーム描画する(&mut self, 入力: フレーム描画入力) -> Result<描画結果, レンダラーエラー> {
        self.フレームを実行する(入力, false)
    }

    /// 1フレーム描画し、提示後にホスト可視バッファへ読み戻す。
    /// GPU同期(フェンス待機)を伴うためスモーク用途と文書化する（判断9）。
    pub fn 一フレーム描画して読み戻す(
        &mut self, 入力: フレーム描画入力
    ) -> Result<読み戻し結果, レンダラーエラー> {
        match self.フレームを実行する(入力, true)? {
            描画結果::見送った(理由) => Ok(読み戻し結果::見送った(理由)),
            描画結果::提示した => Ok(読み戻し結果::読み戻した(self.読み戻しバッファから画像を作る()?)),
        }
    }

    fn フレームを実行する(
        &mut self, 入力: フレーム描画入力, 読み戻し要求: bool
    ) -> Result<描画結果, レンダラーエラー> {
        let 結果 = self.フレームを試行する(入力, 読み戻し要求)?;
        let 結末 = 結末を判定する(結果);
        // 提示まで到達したフレームだけを数える。見送りではフェンス待機が起きないため、発行済みの描画がGPUで完了した保証を得られない。
        match &結末 {
            フレーム結末::提示した => {
                let device = self.環境.device();
                self.シーン描画資源.破棄待ちを一フレーム進める(device);
            }
            フレーム結末::見送った => {}
        }
        self.フレーム進行.結末を反映する(結末);
        Ok(結果)
    }

    fn フレームを試行する(
        &mut self, 入力: フレーム描画入力, 読み戻し要求: bool
    ) -> Result<描画結果, レンダラーエラー> {
        let 視点数 = 入力.視点一覧.視点数();
        if 視点数 != 1 {
            return Err(レンダラーエラー::複数視点提示未対応 { 視点数 });
        }
        let 視点 = 入力.視点一覧.先頭();
        // フレーム型から生値へ戻すGPU境界はこの1箇所（数学DDD。参照: CLAUDE.md「型安全性」）。
        let ビュー射影行列 = 視点.ビュー射影().gpu境界用列優先配列();
        match self.提示.状態() {
            提示状態::最小化中 => return Ok(描画結果::見送った(見送り理由::最小化中)),
            提示状態::陳腐化 { 寸法 } => self.スワップチェーンを再構築する(寸法)?,
            提示状態::描画可能 { .. } => {}
        }
        let Some(許可) = self.提示.描画許可() else {
            // 直前の判別と再構築で描画可能になっているためここへは到達しない。到達不能を型で示せないため見送りとして返す。
            return Ok(描画結果::見送った(見送り理由::スワップチェーン再構築中));
        };
        // 注意: CPU区間時計の開始(prepare)より前に置くため、ここで止まった時間はCPU区間の表に現れない。止まった時間は観測ごとの停止時間msに残る。
        self.実表示計測.表示を待って記録する(許可.スワップチェーンハンドル())?;

        let mut 準備 = prepare::実行する(self, &入力, 視点, &ビュー射影行列)?;
        let 取得セマフォ = 準備.スロット資源.取得セマフォ;
        let Some(取得済み) = acquire::実行する(self, 取得セマフォ, &mut 準備.cpu区間時計)? else {
            return Ok(描画結果::見送った(見送り理由::スワップチェーン再構築中));
        };
        submit::実行する(self, 入力, 読み戻し要求, 準備, 取得済み)
    }
}

/// 失敗(`Err`)は`?`で戻るためこの判定へ到達せず、スロットは据え置かれる。送信済みのフェンスが無いスロットを次フレームがそのまま使い直せる状態にするための規律である。
fn 結末を判定する(結果: 描画結果) -> フレーム結末 {
    match 結果 {
        描画結果::提示した => フレーム結末::提示した,
        描画結果::見送った(_) => フレーム結末::見送った,
    }
}
