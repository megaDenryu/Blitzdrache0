//! 1フレーム実行の本体: 最小化判定 → 再構築判定 → フェンス待機 → UBO書き込み →
//! 取得 → 描画 → 提示。フレームインフライト2のため、フェンス・取得セマフォ・
//! コマンドバッファ・UBOはすべて`現在フレーム添字`で選ぶ（判断13・判断24）。
//! 公開エントリ(`一フレーム描画する`系)は`draw`にある。

use super::レンダラー;
use crate::draw_result::{描画結果, 見送り理由};
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::vulkan;
use crate::vulkan::frame::取得結果;
use crate::vulkan::sync::フレームインフライト数;

impl レンダラー {
    pub(super) fn フレームを実行する(
        &mut self,
        入力: フレーム描画入力,
        読み戻し要求: bool,
    ) -> Result<描画結果, レンダラーエラー> {
        // フレーム型から生値へ戻すGPU境界はこの1箇所（数学DDD。参照: CLAUDE.md「型安全性」）。
        let ビュー射影行列 = 入力.ビュー射影.gpu境界用列優先配列();
        if self.現在の寸法.ゼロ寸法か() {
            return Ok(描画結果::見送った(見送り理由::最小化中));
        }
        if self.再構築が必要 {
            self.スワップチェーンを再構築する()?;
        }

        let フレーム添字 = self.現在フレーム添字;
        let フェンス = self.フレーム同期.フェンス(フレーム添字);
        // 安全性: フェンスは前フレーム(または初期シグナル状態)のGPU完了を表す。
        unsafe { self.device.wait_for_fences(&[フェンス], true, u64::MAX)? };

        // 判断30: このスロットの前回分クエリ結果は、そのGPU完了がいま確定した
        // (フェンス待ち完了)直後に読む。今回の記録がプールをリセットする前に行う。
        if let Some(計測) = &mut self.gpu計測 {
            計測.読み取る(&self.device, フレーム添字);
        }

        // 判断24: UBO書き込みはフェンス待ち後(前回使用のGPU完了後)に行う。スキン行列(判断44)・布(判断54)も同じ規律。
        self.ユニフォームを書き込む(フレーム添字, &入力, &ビュー射影行列)?;
        self.スキン行列を書き込む(フレーム添字, &入力)?;
        self.布フレームを書き込む(フレーム添字, &入力)?;

        let 取得セマフォ = self.フレーム同期.取得セマフォ(フレーム添字);
        let 添字 = match vulkan::frame::acquire::取得する(
            &self.swapchain_loader,
            self.swapchain.handle,
            取得セマフォ,
        )? {
            取得結果::取得した { 添字, 劣化 } => {
                self.再構築が必要 |= 劣化;
                添字
            }
            取得結果::再構築が必要 => {
                self.再構築が必要 = true;
                // 注意: ここでフェンスをリセットしない。acquire失敗時にリセット済みの
                // フェンスが残ると、送信が行われないため誰もシグナルせず、
                // 次周回のwait_for_fencesが永久待ちになる（判断13の要）。
                return Ok(描画結果::見送った(見送り理由::スワップチェーン再構築中));
            }
        };

        if 読み戻し要求 {
            if !self.swapchain.読み戻し対応 {
                return Err(レンダラーエラー::読み戻し非対応);
            }
            self.読み戻しバッファを確保する()?;
        }

        let ui入力 = self.ui描画入力を組み立てる(フレーム添字, 入力.ui描画.as_ref())?;

        // 安全性: acquire成功後・送信直前にリセットする。読み戻しバッファ確保などの
        // 失敗しうる処理をこれより前に済ませておくことで、送信されないままリセット済みの
        // フェンスが残る経路を作らない。
        unsafe { self.device.reset_fences(&[フェンス])? };

        let 布介入件数 = 入力.布.as_ref().map_or(0, |布| 布.介入件数);
        let (提示劣化, 計測マッピング) = self.現在の画像で描画する(
            添字,
            フレーム添字,
            入力.クリア色,
            入力.露出,
            布介入件数,
            読み戻し要求,
            ui入力.as_ref(),
        )?;
        if let Some(計測) = &mut self.gpu計測 {
            計測.直近マッピングを記録する(フレーム添字, 計測マッピング);
        }
        self.再構築が必要 |= 提示劣化;
        self.現在フレーム添字 = (フレーム添字 + 1) % フレームインフライト数;
        Ok(描画結果::提示した)
    }
}
