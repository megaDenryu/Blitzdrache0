//! 1フレーム実行の本体: 最小化判定 → 再構築判定 → フェンス待機 → UBO書き込み →
//! 取得 → 描画 → 提示。フレームインフライト2のため、フェンス・取得セマフォ・
//! コマンドバッファ・UBOはすべて`現在フレーム添字`で選ぶ（判断13・判断24）。
//! 公開エントリ(`一フレーム描画する`系)は`draw`にある。

mod acquire;
mod prepare;
mod submit;

use super::レンダラー;
use crate::draw_result::{描画結果, 見送り理由};
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;

impl レンダラー {
    pub(super) fn フレームを実行する(
        &mut self,
        入力: フレーム描画入力,
        読み戻し要求: bool,
    ) -> Result<描画結果, レンダラーエラー> {
        let 視点数 = 入力.視点一覧.視点数();
        if 視点数 != 1 {
            return Err(レンダラーエラー::複数視点提示未対応 { 視点数 });
        }
        let 視点 = 入力.視点一覧.先頭();
        // フレーム型から生値へ戻すGPU境界はこの1箇所（数学DDD。参照: CLAUDE.md「型安全性」）。
        let ビュー射影行列 = 視点.ビュー射影().gpu境界用列優先配列();
        if self.現在の寸法.ゼロ寸法か() {
            return Ok(描画結果::見送った(見送り理由::最小化中));
        }
        if self.再構築が必要 {
            self.スワップチェーンを再構築する()?;
        }

        let mut 準備 = prepare::実行する(self, &入力, 視点, &ビュー射影行列)?;
        let Some(添字) = acquire::実行する(self, 準備.フレーム添字, &mut 準備.cpu区間時計)? else {
            return Ok(描画結果::見送った(見送り理由::スワップチェーン再構築中));
        };
        submit::実行する(self, 入力, 読み戻し要求, 準備, 添字)
    }
}
