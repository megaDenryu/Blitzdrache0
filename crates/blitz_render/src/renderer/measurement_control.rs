//! ベンチ計測の有効化。描画ループを始める前に一度だけ呼ばれ、`cpu区間計測`と`実表示計測`へ記録を始めさせる。
//! 触れるフィールドはこの2つに限る。
//!
//! 注意: 3つの計測は有効化条件が別々(CPU区間はコマンドライン指定、実表示は拡張と機能の対応可否、パス別GPU時間の
//! フレーム別記録はコマンドライン指定かつタイムスタンプ対応)であり、1つを有効にしても他の状態は変わらない。
//! 共通するのは呼び出し時期だけで、状態としての不変条件は無い。

use super::cpu_timing::CPU区間計測;
use super::レンダラー;
use crate::present_display::実表示計測状況;

impl レンダラー {
    /// ベンチ用CPU区間計測を有効にする。通常実行では計測時計を読まない。
    pub fn cpu区間計測を有効にする(&mut self, ウォームアップフレーム数: u32, 標本容量: usize) {
        self.cpu区間計測 = Some(CPU区間計測::生成する(ウォームアップフレーム数, 標本容量));
    }

    /// ベンチ用の実表示時刻計測を有効にする。戻り値は対応状況であり、非対応なら記録は始まらない。
    pub fn 実表示計測を有効にする(&mut self, ウォームアップ観測数: u32, 標本容量: usize) -> 実表示計測状況 {
        self.実表示計測.記録を開始する(ウォームアップ観測数, 標本容量)
    }

    /// パス別GPU時間の窓へ入る前の生の値の記録を始める。タイムスタンプ非対応のデバイスでは計測そのものが無いため始まらず、
    /// そのことは読み出しが空の列を返すことで表れる(終了時の報告が「記録できなかった」と明示する)。
    pub fn パス別gpu時間のフレーム別記録を始める(&mut self) {
        if let Some(計測) = self.gpu計測.as_mut() {
            計測.フレーム別の記録を始める();
        }
    }
}
