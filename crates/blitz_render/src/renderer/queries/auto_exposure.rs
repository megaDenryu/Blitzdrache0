//! GPU上の自動露出の中身を検収へ渡す局面。呼ばれるのは検収の実行が求めたときだけであり、本番のフレーム経路は1度も通らない。
//!
//! GPUの全作業完了を待ってから読むのは、進行中のフレームが同じバッファを書いている最中に読むと中身が定まらないためである。
//! この待機が本番のフレーム経路に無いことが「露出状態をCPUへ毎フレーム読み戻さない」契約そのものである
//! (`参照: _doc/設計/放射輝度問い合わせ階層.md`「GPU配線の契約」)。

use crate::auto_exposure::自動露出の観測;
use crate::error::レンダラーエラー;
use crate::renderer::レンダラー;

impl レンダラー {
    /// ポスト処理を組まない構成では自動露出の資源そのものが無いため、値が無いことをそのまま返す。
    pub fn 自動露出の観測を読み戻す(&self) -> Result<Option<自動露出の観測>, レンダラーエラー> {
        let Some(ポスト処理) = &self.ポスト処理 else {
            return Ok(None);
        };
        self.環境.gpuの全作業完了を待つ()?;
        let メモリプロパティ = self.環境.メモリプロパティを取得する();
        let 観測 = ポスト処理.自動露出の観測を読み戻す(self.環境.device(), &メモリプロパティ, &self.転送環境)?;
        Ok(Some(観測))
    }
}
