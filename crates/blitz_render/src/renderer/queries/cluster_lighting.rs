//! クラスタの選別が書いた割り当てを検収へ渡す局面。呼ばれるのは検収の実行が求めたときだけであり、本番のフレーム経路は1度も通らない。
//!
//! GPUの全作業完了を待ってから読むのは、進行中のフレームが同じバッファを書いている最中に読むと中身が定まらないためである。
//!
//! 読むのは直近に描き終えたスロットである。巡回は提示したフレームの後に次のスロットへ進むため、現在のスロットは
//! 次に書かれる側であり、最後に書かれたのはその1つ前である。
//!
//! 注意: 直前のフレームが提示へ到達しなかった実行では巡回が進んでおらず、1つ前のスロットは2フレーム前の内容になる。
//! この検収は静止した世界を撮るため、2フレーム前でも同じ割り当てになる。
//!
//! 写像と球の組み立てをこの局面が持つのは、突き合わせる相手が「そのフレームの選別が読んだ値」でなければならず、
//! それを作れるのが毎フレームの書き込みと同じ材料を持つレンダラーだけだからである。

use blitz_math::{ワールド, 位置};

use crate::clustered_lighting::{
    クラスタ選別の割り当て統計, 割り当てを突き合わせて統計を作る, 局所光の影響範囲の球
};
use crate::error::{レンダラーエラー, 照明問い合わせ梱包エラー};
use crate::lighting_input::局所光源列;
use crate::renderer::レンダラー;
use crate::view_input::描画視点;

impl レンダラー {
    pub fn クラスタ選別の割り当て統計を読み戻す(
        &self,
        視点: &描画視点,
        局所光源列: &局所光源列,
    ) -> Result<クラスタ選別の割り当て統計, レンダラーエラー> {
        self.環境.gpuの全作業完了を待つ()?;
        let 写像 = self.クラスタ写像を組み立て直す(視点)?;
        let 球一覧 = ビュー空間の球へ写す(視点, 局所光源列)?;
        let 確保係 = self.環境.資源の確保係を貸す();
        let 読み戻し =
            self.照明問い合わせ資源
                .クラスタ格子を読み戻す(&確保係, &self.転送環境, self.フレーム進行.直近に描いたスロット())?;
        Ok(割り当てを突き合わせて統計を作る(写像, &球一覧, &読み戻し.区間一覧, &読み戻し.光添字列)
            .map_err(照明問い合わせ梱包エラー::クラスタ割り当ての突き合わせ不正)?)
    }
}

/// 世界が宣言した局所光を、選別が読んだのと同じビュー空間の球へ写す。カメラ大域原点を引いてから
/// カメラ相対ビュー変換を適用する順序も、毎フレームの書き込みと選別のコンピュートに揃えてある。
fn ビュー空間の球へ写す(
    視点: &描画視点, 局所光源列: &局所光源列
) -> Result<Vec<局所光の影響範囲の球>, レンダラーエラー> {
    let 変換 = 視点.カメラ相対ビュー変換();
    局所光源列
        .点光源を宣言の順に返す()
        .map(|点光源| {
            let 相対 = 点光源.位置().カメラ相対へ変換する(視点.カメラ大域原点())?;
            let ワールド位置 = 位置::<ワールド>::生成する(相対.x(), 相対.y(), 相対.z());
            Ok(局所光の影響範囲の球::生成する(変換.適用する(ワールド位置), 点光源.影響半径())
                .map_err(照明問い合わせ梱包エラー::クラスタ割り当ての突き合わせ不正)?)
        })
        .collect()
}
