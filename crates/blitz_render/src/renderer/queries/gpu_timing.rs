//! パス別GPU計測の読み出し。触れるのは`gpu計測`フィールドだけであり、他のフィールドにも描画の状態にも触れない。
//!
//! 不変条件は、タイムスタンプ非対応のデバイスで計測そのものが無いとき、どちらの読み出しも空を返すことである。
//! 無言の0ミリ秒や、記録していないことを「1フレームも読めなかった」と見せる値は返さない。

use super::super::レンダラー;
use crate::gpu_pass_timing::フレーム別の標本;
use crate::vulkan;

impl レンダラー {
    /// パス名ごとの直近60フレームの窓の分布を返す(判断30)。タイムスタンプ非対応
    /// デバイスでは空配列(計測できていないことの明示。無言の0ミリ秒は返さない)。
    pub fn パス別gpu時間を取得する(&self) -> Vec<(&'static str, crate::gpu_pass_timing::パス時間の分布)> {
        self.gpu計測
            .as_ref()
            .map(vulkan::gpu_timing::パス別GPU計測::分布一覧を取得する)
            .unwrap_or_default()
    }

    /// パス別GPU時間の窓へ入る前の生の値。記録を始めていなければ空配列である。
    pub fn パス別gpu時間のフレーム別標本を取得する(&self) -> &[フレーム別の標本] {
        self.gpu計測.as_ref().map_or(&[], vulkan::gpu_timing::パス別GPU計測::フレーム別の標本一覧)
    }
}
