//! 読み戻しバッファの確保(必要なら再確保)と、読み戻し画像への変換。
//! 触れるフィールドは`読み戻しバッファ`と、必要容量と形式を決める`提示`、確保と読み取りに要る`環境`に限る。
//! 不変条件として、`Some`である間の容量は現在のスワップチェーン寸法と直前に要求した読み戻し対象のぶんを常に満たす。この確保を経ずに画像化を呼ぶことは呼び出し規律の破れであり、型付きエラーではなくpanicで落とす。

use super::レンダラー;
use crate::error::レンダラーエラー;
use crate::readback_image::読み戻し画像;
use crate::vulkan;
use crate::vulkan::readback::{読み戻し対象, 読み戻し画像の読み出し元};

impl レンダラー {
    /// 現在のスワップチェーン寸法と読み戻し対象のぶんの容量を持つ読み戻しバッファを確保する。
    /// 既存バッファの容量が足りていれば何もしない。
    pub(super) fn 読み戻しバッファを確保する(&mut self, 対象: 読み戻し対象) -> Result<(), レンダラーエラー> {
        let 寸法 = self.提示.寸法();
        let 必要バイト数 = u64::from(寸法.width) * u64::from(寸法.height) * 対象.画素あたりバイト数();
        let 再確保が必要 = match &self.読み戻しバッファ {
            Some(バッファ) => バッファ.容量バイト数() < 必要バイト数,
            None => true,
        };
        if !再確保が必要 {
            return Ok(());
        }
        if let Some(古い) = self.読み戻しバッファ.take() {
            古い.破棄する(self.環境.device());
        }
        let 確保係 = self.環境.資源の確保係を貸す();
        self.読み戻しバッファ = Some(vulkan::readback::読み戻しバッファ::生成する(&確保係, 必要バイト数)?);
        Ok(())
    }

    /// 提示成功直後に読み戻しバッファをホストから読み、提示画像の`読み戻し画像` へ変換する。
    pub(super) fn 読み戻しバッファから提示画像を作る(&self) -> Result<読み戻し画像, レンダラーエラー> {
        self.読み戻し画像の読み出し元().提示画像として開く(self.提示.画像形式())
    }

    /// 提示成功直後の読み戻しバッファを、そのフレームの寸法とともに開く口。対象ごとの変換はこの読み出し元が持つ。
    pub(super) fn 読み戻し画像の読み出し元(&self) -> 読み戻し画像の読み出し元<'_> {
        let バッファ = self
            .読み戻しバッファ
            .as_ref()
            .unwrap_or_else(|| panic!("提示成功時に読み戻しバッファが未確保だった"));
        読み戻し画像の読み出し元::生成する(self.環境.device(), バッファ, self.提示.寸法())
    }
}
