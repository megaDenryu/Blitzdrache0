//! 読み戻しバッファの確保(必要なら再確保)と、読み戻し画像への変換。
//! 触れるフィールドは`読み戻しバッファ`と、必要容量と形式を決める`提示資源`、確保と読み取りに要る`環境`に限る。
//! 不変条件として、`Some`である間の容量は現在のスワップチェーン寸法ぶんを常に満たす。この確保を経ずに画像化を呼ぶことは呼び出し規律の破れであり、型付きエラーではなくpanicで落とす。

use super::レンダラー;
use crate::error::レンダラーエラー;
use crate::readback_image::読み戻し画像;
use crate::vulkan;

impl レンダラー {
    /// 現在のスワップチェーン寸法ぶんの容量を持つ読み戻しバッファを確保する。
    /// 既存バッファの容量が足りていれば何もしない。
    pub(super) fn 読み戻しバッファを確保する(&mut self) -> Result<(), レンダラーエラー> {
        let 寸法 = self.提示資源.寸法();
        let 必要バイト数 = u64::from(寸法.width) * u64::from(寸法.height) * 4;
        let 再確保が必要 = match &self.読み戻しバッファ {
            Some(バッファ) => バッファ.容量バイト数() < 必要バイト数,
            None => true,
        };
        if !再確保が必要 {
            return Ok(());
        }
        if let Some(古い) = self.読み戻しバッファ.take() {
            古い.破棄する(self.環境.device());
        }
        let メモリプロパティ = self.環境.メモリプロパティを取得する();
        self.読み戻しバッファ = Some(vulkan::readback::読み戻しバッファ::生成する(
            self.環境.device(),
            &メモリプロパティ,
            必要バイト数,
        )?);
        Ok(())
    }

    /// 提示成功直後に読み戻しバッファをホストから読み、`読み戻し画像` へ変換する。
    pub(super) fn 読み戻しバッファから画像を作る(&self) -> Result<読み戻し画像, レンダラーエラー> {
        let バッファ = self
            .読み戻しバッファ
            .as_ref()
            .unwrap_or_else(|| panic!("提示成功時に読み戻しバッファが未確保だった"));
        vulkan::readback::読み取る(self.環境.device(), バッファ, self.提示資源.寸法(), self.提示資源.画像形式())
    }
}
