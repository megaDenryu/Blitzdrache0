//! 検収が合成深度を据える公開エントリと、そのフレームの転送パスへ渡す入力の受け渡し。
//! 資源そのものはシーン段階の器(`draw_stage_resources`)が持ち、この入口は寸法の一致だけを見る。
//!
//! 据える形にして毎フレーム渡す形にしないのは、同じ1枚を何度も転送するだけの実行でホストからの書き込みと
//! バッファの確保を毎フレーム繰り返さないためである。据えた後は転送だけが毎フレーム起こる。
//!
//! 据えた後に画面の寸法が変わった場合は、そのフレームの描画を型付きの失敗にする。無言で注入を落とすと、
//! 検収は本番のジオメトリの深度から焼いた可視度を正本と突き合わせることになり、その食い違いを写しの誤りと読む。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「IIaの実装設計」

use super::super::レンダラー;
use crate::error::{フレーム入力不一致エラー, レンダラーエラー};
use crate::local_visibility::{局所可視性エラー, 深度画像, 画像の寸法};
use crate::vulkan::depth_injection::合成深度の注入入力;

impl レンダラー {
    /// いま描いている画面の画素数。検収はこの寸法で合成深度を焼く。
    /// 幅か高さが1のときに失敗を返すのは、`画像の寸法`が中央差分の隣点を軸ごとに1つ要求するためである。
    pub fn 画面の寸法(&self) -> Result<画像の寸法, 局所可視性エラー> {
        let 寸法 = self.提示.寸法();
        画像の寸法::生成する(寸法.width, 寸法.height)
    }

    /// 検収が焼いた合成深度を据える。以降のフレームは深度プリパスの後にこの深度を書き戻してから局所可視度を焼く。
    /// 既に据えてあれば入れ替える。
    pub fn 合成深度を注入する(&mut self, 深度画像: &深度画像) -> Result<(), レンダラーエラー> {
        let 画面 = self.提示.寸法();
        let 寸法 = 深度画像.寸法();
        if 寸法.幅() != 画面.width || 寸法.高さ() != 画面.height {
            return Err(寸法不一致(寸法, 画面.width, 画面.height).into());
        }
        self.環境.gpuの全作業完了を待つ()?;
        let 確保係 = self.環境.資源の確保係を貸す();
        self.描画段階資源.合成深度の注入を据える(&確保係, 深度画像)
    }

    /// そのフレームの転送パスへ渡す入力。据えていなければ`None`であり、パスを1本も積まない。
    pub(in crate::renderer) fn 合成深度の注入入力を組み立てる(
        &self,
    ) -> Result<Option<合成深度の注入入力>, レンダラーエラー> {
        let Some(入力) = self.描画段階資源.合成深度の注入入力() else {
            return Ok(None);
        };
        let 画面 = self.提示.寸法();
        if 入力.寸法 != 画面 {
            let 寸法 = 画像の寸法::生成する(入力.寸法.width, 入力.寸法.height)
                .unwrap_or_else(|誤り| panic!("据えた合成深度の寸法が値域を外れている: {誤り}"));
            return Err(寸法不一致(寸法, 画面.width, 画面.height).into());
        }
        Ok(Some(入力))
    }
}

fn 寸法不一致(与えた: 画像の寸法, 画面の幅: u32, 画面の高さ: u32) -> フレーム入力不一致エラー {
    フレーム入力不一致エラー::合成深度の寸法不一致 {
        与えた幅: 与えた.幅(),
        与えた高さ: 与えた.高さ(),
        画面の幅,
        画面の高さ,
    }
}
