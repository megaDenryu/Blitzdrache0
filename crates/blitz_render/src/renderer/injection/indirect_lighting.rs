//! 検収が遠方環境の派生表現へ解析入力を注入する入口。担うのは「レンダラーが持つ遠方環境の照明資源へ
//! 注入を依頼し、契約が遠方環境の枝でない実行を型付きの失敗で拒む」ことである。
//!
//! 生成の引数へ混ぜず後から呼ぶ形にするのは、注入が本番のフレーム経路に1度も現れないためである。生成の
//! 引数に載せると、遠方環境の資源を作る全経路がこの検収専用の値を運ぶことになる。
//!
//! 呼ぶのはレンダラーを生成した直後の1回だけである。フレームを1枚でも描いた後に呼ぶことは想定しない
//! (注入する値は起動時に決まって以降変わらない)。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」

use super::super::レンダラー;
use crate::distant_environment::{遠方環境の焼かせる解析入力, 遠方環境の解析入力, 遠方環境の解析入力エラー};
use crate::error::レンダラーエラー;
use crate::indirect_lighting::間接照明エラー;

impl レンダラー {
    /// 拡散照度・鏡面畳込み・反射率積分表の中身を解析入力で置き換え、以降のフレームで焼き上げを止める。
    /// 契約が定数近似の実行はそもそも3つの画像を持たないため、資源が無いことを型付きの失敗で返す。
    pub fn 遠方環境の解析入力を注入する(&mut self, 入力: &遠方環境の解析入力) -> Result<(), レンダラーエラー> {
        let 確保係 = self.gpu環境.資源の確保係を貸す();
        let _device = self.gpu環境.device();
        let Some(照明) = self.描画段階資源.遠方環境の照明を借りる() else {
            return Err(間接照明エラー::from(遠方環境の解析入力エラー::遠方環境の資源なし).into());
        };
        照明.解析入力を注入する(&確保係, 入力)
    }

    /// 遠方環境の立方体画像と反射率積分表を与えた値で置き換え、拡散照度と鏡面畳込みは生成側に焼かせる。
    /// 生成側と消費側の連なりを1つの条件で見るための入口である。
    pub fn 遠方環境の焼かせる解析入力を注入する(
        &mut self,
        入力: &遠方環境の焼かせる解析入力,
    ) -> Result<(), レンダラーエラー> {
        let 確保係 = self.gpu環境.資源の確保係を貸す();
        let _device = self.gpu環境.device();
        let Some(照明) = self.描画段階資源.遠方環境の照明を借りる() else {
            return Err(間接照明エラー::from(遠方環境の解析入力エラー::遠方環境の資源なし).into());
        };
        照明.焼かせる解析入力を注入する(&確保係, 入力)
    }
}
