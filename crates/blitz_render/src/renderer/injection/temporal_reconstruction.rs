//! 検収が時間再構成の合成入力を据える公開エントリ。資源そのものは時間再構成の一式が持ち、この入口は寸法の一致だけを見る。
//!
//! 据える形にして毎フレーム渡す形にしないのは、同じ4枚を何度も転送するだけの実行でホストからの書き込みと
//! バッファの確保を毎フレーム繰り返さないためである。据えた後は転送だけが毎フレーム起こる。
//!
//! 据えた後に画面の寸法が変わった場合は、そのフレームの描画を型付きの失敗にする。無言で注入を落とすと、
//! 検収は本番の描画結果を正本と突き合わせることになり、その食い違いを写しの誤りと読む。
//! 参照: `_doc/設計/時間再構成.md`「検収戦略(判断g)」の2

use super::super::レンダラー;
use crate::error::{フレーム入力不一致エラー, レンダラーエラー};
use crate::temporal_reconstruction::時間再構成の合成入力;

impl レンダラー {
    /// 検収が焼いた合成入力を据える。以降のフレームは時間再構成のパスの直前にこの4枚を書き戻してから再構成する。
    /// 既に据えてあれば入れ替える。
    pub fn 時間再構成の合成入力を注入する(
        &mut self, 合成入力: &時間再構成の合成入力
    ) -> Result<(), レンダラーエラー> {
        let 画面 = self.提示.寸法();
        let 寸法 = 合成入力.寸法();
        if 寸法.幅() != 画面.width || 寸法.高さ() != 画面.height {
            return Err(フレーム入力不一致エラー::合成入力の寸法不一致 {
                与えた幅: 寸法.幅(),
                与えた高さ: 寸法.高さ(),
                画面の幅: 画面.width,
                画面の高さ: 画面.height,
            }
            .into());
        }
        self.環境.gpuの全作業完了を待つ()?;
        let メモリプロパティ = self.環境.メモリプロパティを取得する();
        self.時間再構成.合成入力を据える(self.環境.device(), &メモリプロパティ, 合成入力)
    }
}
