//! そのフレームだけ存在しうる描画入力(ポスト処理・スキニング・布・粒子・空)を、各サブシステムから集めて所有する型。
//! 担当する工程は「フレームスロットとそのフレームの値を受け取り、任意段階の入力一式を作る」ことである。
//! 所有と借用を分けているのは、`任意描画入力`が借用の束であり、借用元をフレーム記録の呼び出しより長く生かす必要があるためである。
//! 開発用UIの入力だけはここへ含めない。UIは他と違い外部(blitz_app)から毎フレーム渡される値であり、集める対象を持たない。

use super::レンダラー;
use crate::error::レンダラーエラー;
use crate::vulkan::atmosphere_lut::大気LUT描画入力;
use crate::vulkan::frame::{UI描画入力, スキニング描画入力, 任意描画入力, 布描画入力, 空描画入力, 粒子描画入力};
use crate::vulkan::post_process::ポスト描画入力;
use crate::vulkan::relative_anchor::カメラ相対アンカー;
use crate::vulkan::sync::フレームスロット添字;

pub(super) struct 任意入力の材料 {
    大気lut: Option<大気LUT描画入力>,
    ポスト: Option<ポスト描画入力>,
    スキニング: Option<スキニング描画入力>,
    布: Option<布描画入力>,
    粒子: Option<粒子描画入力>,
    空: Option<空描画入力>,
}

impl レンダラー {
    pub(super) fn 任意入力の材料を集める(
        &self,
        フレーム添字: フレームスロット添字,
        露出: f32,
        布介入件数: u32,
        原点アンカー: カメラ相対アンカー,
    ) -> Result<任意入力の材料, レンダラーエラー> {
        Ok(任意入力の材料 {
            大気lut: self.大気lut描画入力を組み立てる(フレーム添字),
            ポスト: self.ポスト処理.as_ref().map(|一式| 一式.描画入力を作る(露出)),
            スキニング: self.スキニング.as_ref().map(|一式| 一式.描画入力を作る(フレーム添字)),
            布: self.布入力を組み立てる(フレーム添字, 布介入件数, 原点アンカー)?,
            粒子: self.粒子.as_ref().map(|一式| 一式.描画入力を作る(フレーム添字, 原点アンカー)),
            空: self.空描画入力を組み立てる(フレーム添字)?,
        })
    }
}

impl 任意入力の材料 {
    pub(super) fn 借用する<'a>(&'a self, ui: Option<&'a UI描画入力>) -> 任意描画入力<'a> {
        任意描画入力 {
            大気lut: self.大気lut.as_ref(),
            スキニング: self.スキニング.as_ref(),
            布: self.布.as_ref(),
            空: self.空.as_ref(),
            粒子: self.粒子.as_ref(),
            ブルーム: self.ポスト.as_ref().map(|入力| &入力.ブルーム),
            トーンマップ: self.ポスト.as_ref().map(|入力| &入力.トーンマップ),
            ui,
        }
    }
}
