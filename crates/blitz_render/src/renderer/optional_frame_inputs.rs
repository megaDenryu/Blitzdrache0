//! そのフレームだけ存在しうる描画入力(ポスト処理・スキニング・布・粒子・空)を、各サブシステムから集めて所有する型。
//! 担当する工程は「フレームスロットとそのフレームの値を受け取り、任意段階の入力一式を作る」ことである。
//! 所有と借用を分けているのは、`任意描画入力`が借用の束であり、借用元をフレーム記録の呼び出しより長く生かす必要があるためである。
//! 開発用UIの入力だけはここへ含めない。UIは他と違い外部(blitz_app)から毎フレーム渡される値であり、集める対象を持たない。

use super::レンダラー;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::vulkan::atmosphere_lut::大気のベイク済み画像の描画入力;
use crate::vulkan::frame::{
    UI描画入力, スキニング描画入力, 任意描画入力, 布描画入力, 空中遠近合成描画入力, 空描画入力, 粒子描画入力
};
use crate::vulkan::indirect_lighting::間接照明の描画入力;
use crate::vulkan::post_process::ポスト描画入力;
use crate::vulkan::relative_anchor::カメラ相対の基準原点;
use crate::vulkan::sync::フレームスロット添字;

pub(super) struct 任意入力の材料 {
    大気のベイク済み画像: Option<大気のベイク済み画像の描画入力>,
    間接照明: Option<間接照明の描画入力>,
    ポスト: Option<ポスト描画入力>,
    スキニング: Option<スキニング描画入力>,
    布: Option<布描画入力>,
    粒子: Option<粒子描画入力>,
    空: Option<空描画入力>,
    空中遠近合成: Option<空中遠近合成描画入力>,
}

impl レンダラー {
    pub(super) fn 任意入力の材料を集める(
        &mut self,
        フレーム添字: フレームスロット添字,
        入力: &フレーム描画入力<'_>,
        露出: f32,
        布介入件数: u32,
        原点由来の基準原点: カメラ相対の基準原点,
    ) -> Result<任意入力の材料, レンダラーエラー> {
        Ok(任意入力の材料 {
            大気のベイク済み画像: self.大気のベイク済み画像の描画入力を組み立てる(フレーム添字, 入力),
            間接照明: self.描画段階資源.間接照明の描画入力を作る(フレーム添字, 入力)?,
            ポスト: self.ポスト処理.as_ref().map(|一式| 一式.描画入力を作る(露出, 入力.自動露出の経過秒)),
            スキニング: self.スキニング.as_ref().map(|一式| 一式.描画入力を作る(フレーム添字)),
            布: self.布入力を組み立てる(フレーム添字, 布介入件数, 原点由来の基準原点)?,
            粒子: self.粒子.as_ref().map(|一式| 一式.描画入力を作る(フレーム添字, 原点由来の基準原点)),
            空: self.空描画入力を組み立てる(フレーム添字),
            空中遠近合成: self.空中遠近合成入力を組み立てる(フレーム添字, 入力)?,
        })
    }
}

impl 任意入力の材料 {
    pub(super) fn 借用する<'a>(&'a self, ui: Option<&'a UI描画入力>) -> 任意描画入力<'a> {
        任意描画入力 {
            大気のベイク済み画像: self.大気のベイク済み画像.as_ref(),
            間接照明: self.間接照明.as_ref(),
            スキニング: self.スキニング.as_ref(),
            布: self.布.as_ref(),
            空: self.空.as_ref(),
            空中遠近合成: self.空中遠近合成.as_ref(),
            粒子: self.粒子.as_ref(),
            光のにじみ: self.ポスト.as_ref().map(|入力| &入力.光のにじみ),
            明るさの圧縮: self.ポスト.as_ref().map(|入力| &入力.明るさの圧縮),
            自動露出: self.ポスト.as_ref().and_then(|入力| 入力.自動露出.as_ref()),
            ui,
        }
    }
}
