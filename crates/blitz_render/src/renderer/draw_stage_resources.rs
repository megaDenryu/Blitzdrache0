//! 描画段階がGPUへ発行するときに束縛するパイプラインと、そのパイプラインレイアウト・専用ディスクリプタ・専用画像の所有者。
//! 空段階・影段階の布専用経路が使う現物を具体フィールドで持ち、段階の種類を鍵にした表では持たない。
//! シーンと影の本体のパイプラインはここに無い。材質を読む描画族はパイプラインキーで選ぶため、`vulkan::pipeline_ledger`の台帳が持つ。
//! 空段階の大気のベイク済み画像のように段階が専有する画像もここが持つ。段階に属する資源をレンダラー直下へ足さないことがこの器の目的であり、
//! 資源の種類がパイプラインかどうかで置き場所を分けると目的が達せられないためである。
//! 段階が増えるたびにレンダラー直下のフィールドが増えることを止めるためにこの型がある
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「描画段階資源の器と布専用シャドウ経路」)。
//! 破棄はレンダラーの単一破棄元(`renderer/destroy.rs`)がこの型の`破棄する`を1回呼ぶ形を保つ。
//! 生成はレンダラー生成時の1回だけの局面であり、`create`が担う。段階ごとの操作は、大気のベイク済み画像だけに触れるものを`atmosphere`、
//! 空段階だけに触れるものを`sky`が持つ。

mod atmosphere;
mod create;
mod indirect_lighting;
mod sky;

pub(super) use create::生成要求;

use crate::error::レンダラーエラー;
use crate::indirect_lighting::焼き上げ本数の見込み;
use crate::vulkan;
use crate::vulkan::tracked_device::GPUデバイス;

pub(super) struct 描画段階資源 {
    /// フレーム構成に空段階があるときだけ`Some`。有無はフレーム描画入力の空と常に一致させる。方式はこの型が持つ。
    空: Option<vulkan::sky_stage::空段階資源>,
    /// フレーム構成に空段階があるときだけ`Some`。有無はフレーム描画入力の大気媒体と常に一致させる。
    大気のベイク済み画像: Option<vulkan::atmosphere_lut::大気のベイク済み画像一式>,
    /// 照明問い合わせ契約が遠方環境の枝のときだけ`Some`。有無はフレーム描画入力の遠方環境と常に一致させる。
    遠方環境の照明: Option<vulkan::indirect_lighting::遠方環境の照明資源>,
    /// フレーム構成に布シミュレーション段階があるときだけ`Some`。有無はレンダラーの布一式の有無と常に一致する(`レンダラー::生成する`の`構成と素材を検査する`が対応を検査済み)。
    布シャドウ: Option<vulkan::cloth_shadow::布シャドウ資源>,
}

impl 描画段階資源 {
    pub(super) fn 生成する(要求: 生成要求<'_>) -> Result<Self, レンダラーエラー> {
        create::生成する(要求)
    }

    /// 照明問い合わせのセットへ結ぶ遠方環境の3つの画像。遠方環境の照明資源を持たない契約では`None`を返し、
    /// セットの束縛レイアウトとの食い違いを結ぶ側が落とす。
    pub(super) fn 遠方環境の束縛先(&self) -> Option<vulkan::descriptor::lighting_set::distant_environment::遠方環境の束縛先> {
        self.遠方環境の照明
            .as_ref()
            .map(vulkan::indirect_lighting::遠方環境の照明資源::照明問い合わせへの束縛先)
    }

    /// 遠方環境の契約が1フレームに積む本数の見込み。定数近似の契約では資源そのものが無いため`None`を返す。
    pub(super) fn 間接照明の焼き上げ本数の見込み(&self) -> Option<焼き上げ本数の見込み> {
        self.遠方環境の照明
            .as_ref()
            .map(vulkan::indirect_lighting::遠方環境の照明資源::焼き上げ本数の見込み)
    }

    /// 遠方環境の照明資源への可変の参照。検収の注入だけが使う入口であり、本番のフレーム経路は通らない。
    pub(super) fn 遠方環境の照明を借りる(&mut self) -> Option<&mut vulkan::indirect_lighting::遠方環境の照明資源> {
        self.遠方環境の照明.as_mut()
    }

    /// 布をシャドウパスへ記録するときの束縛先。布無しの構成では`None`を返し、布一式との有無の食い違いを呼び出し元が失敗させる。
    pub(super) fn 布シャドウ描画入力を作る(&self) -> Option<vulkan::frame::布シャドウ描画入力> {
        self.布シャドウ.as_ref().map(vulkan::cloth_shadow::布シャドウ資源::描画入力を作る)
    }

    /// 布シャドウ・空・遠方環境の照明・大気のベイク済み画像の順に破棄する。生成の逆順で片付ける。
    /// 空と遠方環境の照明を大気のベイク済み画像より先に置くのは、どちらのディスクリプタも大気のベイク済み画像の画像ビューを結んでいるためである。
    /// 前提: レンダラー全体の破棄順は renderer/destroy.rs が持ち、この束はその1段として呼ばれる(GPU待機済み)。
    pub(super) fn 破棄する(&self, device: &GPUデバイス) {
        if let Some(布シャドウ) = &self.布シャドウ {
            布シャドウ.破棄する(device);
        }
        if let Some(空) = &self.空 {
            空.破棄する(device);
        }
        if let Some(遠方環境の照明) = &self.遠方環境の照明 {
            遠方環境の照明.破棄する(device);
        }
        if let Some(大気のベイク済み画像) = &self.大気のベイク済み画像 {
            大気のベイク済み画像.破棄する(device);
        }
    }
}
