//! 描画束の追加と解除の公開API。呼び出し元が世界の区画を読み込んだときに束を足し、不要になったときに外すための入口である。
//!
//! 起動時のシーン全体も1つの束であり、この経路で足す束と同じ扱いになる。束の識別子の意味はレンダラーが知らない
//! (参照: `crate::draw_bundle_id`)。解除は即座の破棄ではなく破棄待ちへの移動であり、実際の解放はGPUが使い終わってから起きる。

use super::scene_draw_resources::束追加材料;
use super::レンダラー;
use crate::draw_bundle_id::描画束ID;
use crate::error::レンダラーエラー;
use crate::render_scene_material::描画シーン素材;

/// 提示が止まっている間に溜めてよい破棄待ちの上限。通常は進行中フレーム数ぶんのフレームで解放されるため、
/// この水準に達するのは提示が長く止まったときだけである。
const 見送り中の破棄待ち上限: usize = 64;

impl レンダラー {
    /// 描画対象の束を1つ足す。`device_wait_idle`を伴わないため、進行中のフレームを止めずに追加できる。
    /// 注意: 同じIDの束を解除せずに追加するのは呼び出し元のバグであり、破られた不変条件として停止する。
    pub fn 描画束を追加する(&mut self, id: 描画束ID, 描画シーン: &描画シーン素材) -> Result<(), レンダラーエラー> {
        let メモリプロパティ = self.環境.メモリプロパティを取得する();
        let 材料 = 束追加材料 {
            物理デバイス問い合わせ: self.環境.物理デバイス問い合わせ(),
            メモリプロパティ: &メモリプロパティ,
            転送環境: &self.転送環境,
            シェーダー定数: &self.シェーダー定数,
            シャドウマップ: &self.シャドウマップ,
        };
        self.シーン描画資源.束を追加する(self.環境.device(), 材料, id, 描画シーン.描画対象一覧())
    }

    /// 束を描画対象から外す。GPUが使い終わるまでフレームを数えてから解放するため、この呼び出し自体はGPU同期を伴わない。
    /// 該当するIDが無ければ`false`を返す。解除済みの束を再び解除しても異常ではない。
    pub fn 描画束を解除する(&mut self, id: 描画束ID) -> bool {
        self.シーン描画資源.束を解除予約する(id)
    }

    /// 実際にGPU資源を破棄し終えた束のIDを受け皿へ移して空にする。解除の予約は破棄そのものではないため、
    /// 資源の会計を持つ呼び出し元はこの引き取りを根拠にしてだけ使用量を減らしてよい。毎フレーム1回呼ぶ。
    /// 受け皿を呼び出し元が使い回す形にするのは、移動なら双方の容量が安定し、破棄バッチごとのヒープ再確保を避けられるためである。
    pub fn 実破棄済み描画束を引き取る(&mut self, 受け皿: &mut Vec<描画束ID>) {
        受け皿.clear();
        self.シーン描画資源.実破棄済みを引き取る(受け皿);
    }

    /// 提示が止まるとフレームを数える経路が動かず、解除済み束のGPU資源が解放されないまま溜まる。
    /// 実測では提示が止まった約20秒で専用VRAMが83MiBから1,145MiBへ増えた(参照: `_doc/計測/OW2第10段_2026-07-26.md`)。
    /// 注意: GPUの全作業完了を待つのは描画が進んでいない見送りフレームだけであり、通常のフレームペーシングには影響しない。
    pub(super) fn 見送り中の破棄待ちを解放する(&mut self) -> Result<(), レンダラーエラー> {
        if self.シーン描画資源.破棄待ち件数() < 見送り中の破棄待ち上限 {
            return Ok(());
        }
        self.環境.gpuの全作業完了を待つ()?;
        let device = self.環境.device();
        self.シーン描画資源.破棄待ちを全て破棄する(device);
        Ok(())
    }
}
