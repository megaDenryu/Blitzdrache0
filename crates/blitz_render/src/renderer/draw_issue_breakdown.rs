//! 1フレームの描画発行の内訳。パスごとの発行回数と、その発行が描いた個体の総数を別々に持つ。
//! 2つを分けるのは、直接インスタンス描画では発行回数が個体数に比例せず、群と段の数だけで決まることを計器で示すためである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「描画発行」

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 描画発行内訳 {
    シーンパス発行数: usize,
    シャドウパス発行数: usize,
    シーンパス個体数: u64,
    シャドウパス個体数: u64,
}

impl 描画発行内訳 {
    pub(crate) fn 生成する(
        シーンパス発行数: usize, シャドウパス発行数: usize, シーンパス個体数: u64, シャドウパス個体数: u64
    ) -> Self {
        Self {
            シーンパス発行数,
            シャドウパス発行数,
            シーンパス個体数,
            シャドウパス個体数,
        }
    }

    pub fn シーンパス発行数(&self) -> usize {
        self.シーンパス発行数
    }

    pub fn シャドウパス発行数(&self) -> usize {
        self.シャドウパス発行数
    }

    pub fn シーンパス個体数(&self) -> u64 {
        self.シーンパス個体数
    }

    pub fn シャドウパス個体数(&self) -> u64 {
        self.シャドウパス個体数
    }
}
