//! 1フレームの描画発行の内訳。可視ID列の区間を持つパスごとに、すなわちシーンと帯0から帯3のそれぞれについて別々に持つ。
//! パスを分けて数えるのは、シーンパスがカメラ視錐台、帯ごとのシャドウパスがその帯のライトビュー射影から導いた視錐台という
//! 別々の範囲で個体を絞り、一方の可視集合を他方へ流用しないという不変条件を数字で示すためである
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の帯別区間(4区分並べの後継)」)。
//! 帯別の可視数を足した値は、複数の帯へ同時に所属する個体を重複して数える。「影を落とす個体が1体も落ちていない」ことは
//! この和ではなく、群選択計数が持つ帯和集合可視数で見る。
//! パス1つぶんの数は`pass_issue`、LOD段ごとの個体数は`stage_counts`にある。

mod pass_issue;
mod stage_counts;

pub use pass_issue::パス別描画発行;
pub use stage_counts::段別個体数;

use crate::visible_instance_selection::{可視ID列を読むパス数, 可視パス};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 描画発行内訳 {
    パス別: [パス別描画発行; 可視ID列を読むパス数],
}

impl 描画発行内訳 {
    pub(crate) fn 生成する(パス別: [パス別描画発行; 可視ID列を読むパス数]) -> Self {
        Self { パス別 }
    }

    pub fn パス(&self, パス: 可視パス) -> &パス別描画発行 {
        &self.パス別[パス.添字()]
    }
}
