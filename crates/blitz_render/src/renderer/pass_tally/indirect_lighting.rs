//! 間接照明の表現を焼くパスの実行数の記録。担当するのは「フレームごとにレンダーグラフへ積まれた本数を足し込み、
//! 遠方環境を焼き直したフレームの数を別に数える」ことである。
//!
//! 数える場所をグラフの積み上げ側に置くのは、焼き直しの指示から本数を推し量ると、指示と実際に積まれたパスが
//! 食い違ったときにその食い違いを見逃すためである。数えているのはGPUへ発行される本数そのものである。
//!
//! 大気の記録のように先頭フレームの列を持たないのは、パスの種類ごとの内訳が計画の単体テストで反証済みであり、
//! 実行時の判定に要るのが「定数近似の契約では1本も積まない」ことだからである。内訳の実測が要るのは、
//! 本番の世界が遠方環境の契約を選ぶ段(3-Ic-3)からである。

use crate::distant_environment::間接照明生成パス数;

#[derive(Debug, Clone, Default)]
pub struct 間接照明生成パス数の記録 {
    数えたフレーム数: u64,
    焼き直したフレーム数: u64,
    生成パスの総数: u64,
}

impl 間接照明生成パス数の記録 {
    pub(crate) fn 新規() -> Self {
        Self::default()
    }

    /// 1フレームぶんの内訳を記録する。呼ぶのはコマンド記録を終えたフレームだけである。
    pub(crate) fn 記録する(&mut self, 本数: 間接照明生成パス数) {
        self.数えたフレーム数 += 1;
        if 本数.遠方環境 > 0 {
            self.焼き直したフレーム数 += 1;
        }
        self.生成パスの総数 += u64::from(本数.合計());
    }

    pub fn 数えたフレーム数(&self) -> u64 {
        self.数えたフレーム数
    }

    /// 遠方環境を焼き直したフレームの数。定数近似の契約では資源が無いため常に0である。
    pub fn 焼き直したフレーム数(&self) -> u64 {
        self.焼き直したフレーム数
    }

    pub fn 生成パスの総数(&self) -> u64 {
        self.生成パスの総数
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 焼かないフレームだけなら総数も焼き直しも0のまま数えたフレーム数だけが伸びる() {
        let mut 記録 = 間接照明生成パス数の記録::新規();
        記録.記録する(間接照明生成パス数::焼かない());
        記録.記録する(間接照明生成パス数::焼かない());
        assert_eq!(記録.数えたフレーム数(), 2);
        assert_eq!(記録.焼き直したフレーム数(), 0);
        assert_eq!(記録.生成パスの総数(), 0);
    }

    #[test]
    fn 焼いたフレームは内訳の合計を総数へ足す() {
        let mut 記録 = 間接照明生成パス数の記録::新規();
        記録.記録する(間接照明生成パス数 {
            遠方環境用スカイビュー: 1,
            遠方環境: 1,
            最詳細段の複製: 1,
            拡散照度: 1,
            鏡面畳込み: 5,
            反射率積分表: 1,
        });
        assert_eq!(記録.焼き直したフレーム数(), 1);
        assert_eq!(記録.生成パスの総数(), 10);
    }
}
