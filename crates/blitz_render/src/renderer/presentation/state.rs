//! 提示資源が要求寸法に追従しているかどうかの状態と、その状態を移す3つの遷移。
//! 状態を動かす出来事は寸法変更の通知・陳腐化の観測・再構築の完了の3つだけであるため、
//! 真偽値の書き換えを呼び出し側へ散らさずこの3つのメソッドに集める。
//! 最小化中は要求寸法を持たない状態として表すため、最小化中から描画可能へ直接移る遷移が存在しない。
//! 最小化からの復帰は必ず非ゼロ寸法の通知を経る。
//! GPUを必要としない値の遷移だけで閉じているため、この規則はユニットテストで確かめられる。

#[cfg(test)]
mod state_tests;

use crate::extent::{ウィンドウ寸法, 非ゼロ寸法};

/// 提示資源の状態。フレーム開始時の分岐はこの3つと1対1に対応する。
///
/// 注意: `描画可能`は「最後に観測した時点では要求寸法に追従していた」以上を意味しない。判別と
/// `vkAcquireNextImageKHR`のあいだにコンポジタの都合で陳腐化しうるため、スワップチェーンが実際に
/// 有効であることはこの型では保証できない。実際の有効性は取得と提示の戻り値だけが答える。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(in crate::renderer) enum 提示状態 {
    /// ウィンドウがゼロ寸法。スワップチェーンを触ってはならず、作り直す先の要求寸法も持たない。
    最小化中,
    /// 要求寸法に対して資源が古い。描画の前に作り直す。
    陳腐化 { 寸法: 非ゼロ寸法 },
    /// 資源は要求寸法に追従しており、描画に使える。
    描画可能 { 寸法: 非ゼロ寸法 },
}

impl 提示状態 {
    /// 生成直後の状態。要求寸法で資源を作った直後であるため、非ゼロ寸法なら描画可能から始まる。
    pub(super) fn 生成直後(寸法: ウィンドウ寸法) -> Self {
        match 非ゼロ寸法::生成する(寸法) {
            Some(寸法) => Self::描画可能 { 寸法 },
            None => Self::最小化中,
        }
    }

    /// ウィンドウ寸法の通知を受ける。通知は要求寸法そのものを差し替えるため、移る先は今の状態に依らない。
    pub(super) fn 寸法変更を受ける(self, 寸法: ウィンドウ寸法) -> Self {
        match 非ゼロ寸法::生成する(寸法) {
            Some(寸法) => Self::陳腐化 { 寸法 },
            None => Self::最小化中,
        }
    }

    /// 取得または提示が報告した陳腐化を反映する。
    pub(super) fn 陳腐化した(self) -> Self {
        match self {
            // 最小化中は要求寸法を持たないため陳腐化を表せない。次の非ゼロ寸法の通知が陳腐化を作る。
            Self::最小化中 => Self::最小化中,
            Self::陳腐化 { 寸法 } | Self::描画可能 { 寸法 } => Self::陳腐化 { 寸法 },
        }
    }

    /// 資源の作り直しが完了したことを反映する。
    pub(super) fn 再構築を終えた(self) -> Self {
        match self {
            // 最小化中には作り直す先の要求寸法が無いため、この遷移では描画可能へ移らない。最小化からの復帰は非ゼロ寸法の通知が担う。
            Self::最小化中 => Self::最小化中,
            Self::陳腐化 { 寸法 } | Self::描画可能 { 寸法 } => Self::描画可能 { 寸法 },
        }
    }
}
