#![allow(clippy::unwrap_used)]

use super::提示状態;
use crate::extent::{ウィンドウ寸法, 非ゼロ寸法};

fn 通知(幅: u32, 高さ: u32) -> ウィンドウ寸法 {
    ウィンドウ寸法::生成する(幅, 高さ)
}

fn 陳腐化(幅: u32, 高さ: u32) -> 提示状態 {
    提示状態::陳腐化 {
        寸法: 非ゼロ寸法::生成する(通知(幅, 高さ)).unwrap(),
    }
}

fn 描画可能(幅: u32, 高さ: u32) -> 提示状態 {
    提示状態::描画可能 {
        寸法: 非ゼロ寸法::生成する(通知(幅, 高さ)).unwrap(),
    }
}

#[test]
fn 非ゼロ寸法での生成直後は描画可能から始まる() {
    assert_eq!(提示状態::生成直後(通知(800, 600)), 描画可能(800, 600));
}

#[test]
fn ゼロ寸法での生成直後は最小化中から始まる() {
    assert_eq!(提示状態::生成直後(通知(0, 0)), 提示状態::最小化中);
}

#[test]
fn ゼロ寸法の通知で最小化中へ移る() {
    assert_eq!(描画可能(800, 600).寸法変更を受ける(通知(0, 0)), 提示状態::最小化中);
}

#[test]
fn 最小化中が非ゼロ寸法の通知を受けると陳腐化へ移る() {
    assert_eq!(提示状態::最小化中.寸法変更を受ける(通知(640, 480)), 陳腐化(640, 480));
}

#[test]
fn 描画可能が非ゼロ寸法の通知を受けると新しい寸法の陳腐化へ移る() {
    assert_eq!(描画可能(800, 600).寸法変更を受ける(通知(1280, 720)), 陳腐化(1280, 720));
}

#[test]
fn 陳腐化が非ゼロ寸法の通知を受けると要求寸法だけが変わる() {
    assert_eq!(陳腐化(800, 600).寸法変更を受ける(通知(1280, 720)), 陳腐化(1280, 720));
}

#[test]
fn 描画可能が陳腐化を報告されると寸法を保って陳腐化へ移る() {
    assert_eq!(描画可能(800, 600).陳腐化した(), 陳腐化(800, 600));
}

#[test]
fn 陳腐化がさらに陳腐化を報告されても寸法を保つ() {
    assert_eq!(陳腐化(800, 600).陳腐化した(), 陳腐化(800, 600));
}

#[test]
fn 最小化中は陳腐化を報告されても最小化中のままである() {
    assert_eq!(提示状態::最小化中.陳腐化した(), 提示状態::最小化中);
}

#[test]
fn 陳腐化は再構築を終えると寸法を保って描画可能へ戻る() {
    assert_eq!(陳腐化(1280, 720).再構築を終えた(), 描画可能(1280, 720));
}

#[test]
fn 描画可能は再構築を終えても描画可能のままである() {
    assert_eq!(描画可能(800, 600).再構築を終えた(), 描画可能(800, 600));
}

#[test]
fn 最小化中は再構築を終えても描画可能へ移らない() {
    assert_eq!(提示状態::最小化中.再構築を終えた(), 提示状態::最小化中);
}

#[test]
fn 最小化からの復帰は非ゼロ寸法の通知と再構築の両方を要する() {
    let 通知後 = 提示状態::最小化中.寸法変更を受ける(通知(640, 480));
    assert_eq!(通知後, 陳腐化(640, 480));
    assert_eq!(通知後.再構築を終えた(), 描画可能(640, 480));
}
