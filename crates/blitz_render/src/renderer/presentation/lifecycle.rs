//! ライフサイクル局面: 起動時に1度の生成、寸法変更を受けた次フレームに1度の作り直し、終了時に1度の破棄。
//! 資源の作り直しと状態の`描画可能`への移行は必ず対で起きるため、両方をこの1箇所で行う。
//!
//! 前提: 作り直しと破棄は、GPU上の全作業の完了待ちを呼び出し元が済ませてから呼ぶ(旧資源の破棄を含むため)。
//! 参照: crates/blitz_render/src/renderer/destroy.rs がレンダラー全体の破棄順を持つ。

use super::{提示, 提示状態};
use crate::error::レンダラーエラー;
use crate::extent::{ウィンドウ寸法, 非ゼロ寸法};
use crate::renderer::present_resources::提示資源;
use crate::vulkan::gpu_environment::GPU環境;

impl 提示 {
    /// 要求寸法で資源を作る。作った直後の資源はその寸法に追従しているため、非ゼロ寸法なら描画可能から始まる。
    pub(in crate::renderer) fn 生成する(環境: &GPU環境, 要求寸法: ウィンドウ寸法) -> Result<Self, レンダラーエラー> {
        Ok(Self {
            資源: 提示資源::生成する(環境, 要求寸法)?,
            状態: 提示状態::生成直後(要求寸法),
        })
    }

    /// 陳腐化した資源を要求寸法で作り直し、描画可能へ移す。
    ///
    /// 前提: 呼び出し元は`陳腐化`から取り出した寸法を渡す。そのため作り直した資源の寸法と状態の要求寸法は一致する。
    /// 注意: 作り直しが失敗したときは状態を動かさない。資源は使用不能なまま陳腐化として残り、呼び出し元がエラーを上位へ伝える。
    pub(in crate::renderer) fn 作り直す(&mut self, 環境: &GPU環境, 要求寸法: 非ゼロ寸法) -> Result<(), レンダラーエラー> {
        self.資源.作り直す(環境, 要求寸法)?;
        self.状態 = self.状態.再構築を終えた();
        Ok(())
    }

    pub(in crate::renderer) fn 破棄する(&self, 環境: &GPU環境) {
        self.資源.破棄する(環境);
    }
}
