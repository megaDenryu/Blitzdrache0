//! 布フレーム入力(介入・カプセル定数)の毎フレーム書き込みと、布の描画入力の組み立て(判断53・54)。
//! 触れるフィールドは`布`・`環境`と、布が束縛する外部資源の出どころである`描画段階資源`・`シーン描画資源`に限る。
//! 不変条件として`布`の有無とフレーム描画入力の布の有無は常に一致し、不一致は型付きエラーにする。

use super::レンダラー;
use crate::error::{レンダラーエラー, 布エラー};
use crate::frame_input::フレーム描画入力;
use crate::vulkan::sync::フレームスロット添字;

impl レンダラー {
    /// 前提: 呼び出しはこのスロットのフェンス待ち後(判断24のUBO書き込みと同じ規律)。
    pub(super) fn 布フレームを書き込む(
        &self,
        フレーム添字: フレームスロット添字,
        入力: &フレーム描画入力<'_>,
    ) -> Result<(), レンダラーエラー> {
        match (&self.布, &入力.布) {
            (Some(布), Some(布入力)) => 布.フレーム入力を書き込む(self.環境.device(), フレーム添字, 布入力),
            (None, None) => Ok(()),
            (Some(_), None) => Err(布エラー::入力不一致("布付きレンダラーなのに布入力が未指定".to_string()).into()),
            (None, Some(_)) => Err(布エラー::入力不一致("布無しレンダラーに布入力が指定された".to_string()).into()),
        }
    }

    /// 布の1フレーム描画入力を組み立てる(`draw_dispatch`用)。介入件数はフレーム入力から渡す。
    /// 布が束縛するシャドウパイプラインとディスクリプタセットは布一式の外にあるため、ここで集めて外部資源として渡す。
    pub(super) fn 布入力を組み立てる(
        &self,
        フレーム添字: フレームスロット添字,
        介入件数: u32,
        相対アンカー: crate::vulkan::relative_anchor::カメラ相対アンカー,
    ) -> Result<Option<crate::vulkan::frame::布描画入力>, レンダラーエラー> {
        let Some(一式) = self.布.as_ref() else {
            return Ok(None);
        };
        let Some(シーンディスクリプタセット) = self.シーン描画資源.先頭描画対象のディスクリプタセット(フレーム添字)
        else {
            return Err(布エラー::束縛先なし.into());
        };
        let 外部資源 = crate::vulkan::frame::布描画の外部資源 {
            シャドウpipeline: self.描画段階資源.シャドウpipeline(),
            シャドウlayout: self.描画段階資源.シャドウlayout(),
            シーンディスクリプタセット,
        };
        Ok(Some(一式.描画入力を作る(フレーム添字, 介入件数, 相対アンカー, 外部資源)))
    }
}
