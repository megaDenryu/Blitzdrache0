//! アセットホットリロード時のシーン差し替え。device_wait_idle後に描画対象数に連動する資源の束を作り直し、
//! パイプラインは互換レイアウトのまま維持する。

use super::scene_draw_resources::{シーン描画資源, シーン描画資源生成要求};
use super::レンダラー;
use crate::error::レンダラーエラー;
use crate::render_scene_material::描画シーン素材;

impl レンダラー {
    /// 新しい束の生成に失敗したときは旧い束を保持したままエラーを返す(呼び出し元のblitz_appはこれを「読み込み失敗、旧シーン継続」として扱う)。
    pub fn シーンを差し替える(&mut self, 描画シーン: 描画シーン素材) -> Result<(), レンダラーエラー> {
        // M8最小実装の制約(判断44): スキニングバッファの再構築が未実装のため、
        // スキン付きシーンを保持中の差し替えは型付きエラーで拒否する(無言の壊れた描画をしない)。
        if self.スキニング.is_some() {
            return Err(レンダラーエラー::スキン付きシーン差し替え未対応);
        }
        // 旧ジオメトリ・旧テクスチャの破棄前にGPU使用完了を待つ。
        self.環境.gpuの全作業完了を待つ()?;

        let device = self.環境.device();
        let メモリプロパティ = self.環境.メモリプロパティを取得する();

        let 新しい束 = シーン描画資源::生成する(
            device,
            シーン描画資源生成要求 {
                物理デバイス問い合わせ: self.環境.物理デバイス問い合わせ(),
                メモリプロパティ: &メモリプロパティ,
                転送環境: &self.転送環境,
                ユニフォーム: &self.ユニフォーム,
                シャドウマップ: &self.シャドウマップ,
                描画シーン: &描画シーン,
            },
        )?;
        let 旧い束 = std::mem::replace(&mut self.シーン描画資源, 新しい束);
        旧い束.破棄する(device);
        Ok(())
    }
}
