//! アセットホットリロード時のシーン差し替え。起動シーンの束を新しい内容へ差し替えるだけであり、
//! パイプラインは互換レイアウトのまま維持する。
//!
//! 注意: `device_wait_idle`を使わない。材質は完全に構築した資源表世代を公開してから旧世代をフェンス通過後に退役させ、
//! ジオメトリは束の解除予約と同じ破棄待ちの規律で解放するため、差し替えで進行中のフレームを止める必要がない
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「ディスクリプタ索引の採用範囲」)。
//!
//! 差し替えは原子的である。新しい材質を下書きとして積んで容量と梱包を確かめ、新しい束のGPU資源を作り、
//! そのすべてが通ったときにだけ下書きを確定して旧い束を破棄待ちへ移す。どこで落ちても旧い束・公開中の世代・
//! 登録簿の中身と並び・世代の作り直しの要否は差し替え前のままであり、呼び出し元は`Err`を
//! 「読み込み失敗、旧シーン継続」としてそのまま扱える。

use super::scene_draw_resources::{束追加材料, 起動シーンの束ID};
use super::レンダラー;
use crate::error::レンダラーエラー;
use crate::render_scene_material::描画シーン素材;

impl レンダラー {
    pub fn シーンを差し替える(&mut self, 描画シーン: 描画シーン素材) -> Result<(), レンダラーエラー> {
        // M8最小実装の制約(判断44): スキニングバッファの再構築が未実装のため、
        // スキン付きシーンを保持中の差し替えは型付きエラーで拒否する(無言の壊れた描画をしない)。
        if self.スキニング.is_some() {
            return Err(レンダラーエラー::スキン付きシーン差し替え未対応);
        }
        let (材質id一覧, 下書き) = self.材質資源表.束の材質を下書きする(起動シーンの束ID, 描画シーン.描画対象一覧())?;
        let メモリプロパティ = self.環境.メモリプロパティを取得する();
        let 材料 = 束追加材料 {
            メモリプロパティ: &メモリプロパティ,
            転送環境: &self.転送環境,
            セットレイアウト: &self.セットレイアウト,
            材質id一覧: &材質id一覧,
        };
        let 結果 = self
            .シーン描画資源
            .束を差し替える(self.環境.device(), 材料, 起動シーンの束ID, 描画シーン.描画対象一覧());
        match 結果 {
            Ok(()) => {
                self.材質資源表.下書きを確定する(下書き);
                Ok(())
            }
            Err(誤り) => {
                self.材質資源表.下書きを取り消す(下書き);
                Err(誤り)
            }
        }
    }
}
