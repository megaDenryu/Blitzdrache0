//! 照明問い合わせ資源の内容を組み立てる工程。受け取るのは1フレームの分解済み照明入力と描画視点、
//! 返すのはGPUへ書けるヘッダと2つのレコード列である。レンダラーの状態には触れない。
//!
//! 局所光の位置だけをカメラ相対へ狭めるのは、方向光の方向が平行移動で変わらないためである。
//! 現行の直接光は方向光1件と、世界が宣言した件数の局所光源列である。

#[cfg(test)]
mod origin_tests;

use blitz_math::大域ワールド位置;

use crate::clustered_lighting::クラスタ写像;
use crate::distant_environment::遠方環境の入力;
use crate::error::レンダラーエラー;
use crate::frame_lighting::{フレーム照明入力, 直接光入力, 間接照明入力};
use crate::lighting_input::局所光源列;
use crate::view_input::描画視点;
use crate::vulkan::lighting_query::{
    ヘッダの間接照明, 局所光レコードの並び, 局所光レコード内容, 方向光レコード内容, 照明問い合わせヘッダ内容
};

/// そのフレームスロットの3本のバッファへ渡す内容。件数はヘッダが持ち、実体は2つの列が持つ。
/// 列を固定長の枠で持つのは、件数がフレームごとに変わってもヒープ確保を作らないためである。
pub(super) struct 照明問い合わせの書き込み内容 {
    pub(super) ヘッダ: 照明問い合わせヘッダ内容,
    pub(super) 方向光一覧: [方向光レコード内容; 1],
    pub(super) 局所光一覧: 局所光レコードの並び,
}

/// 遠方環境の入力の有無がヘッダの間接照明の枝を決める。有無と照明問い合わせ契約の一致は
/// `draw_stage_resources/indirect_lighting.rs`が同じフレームの中で型付きエラーとして確かめるため、ここでは枝を選ぶだけである。
pub(super) fn 照明問い合わせの書き込み内容を組み立てる(
    照明: &フレーム照明入力,
    遠方環境: Option<&遠方環境の入力>,
    視点: &描画視点,
    クラスタ写像: クラスタ写像,
) -> Result<照明問い合わせの書き込み内容, レンダラーエラー> {
    let 直接光入力::固定 { 方向光, 局所光源列 } = 照明.直接光();
    let 間接照明入力::定数近似(環境光) = 照明.間接照明();
    let 間接照明 = match 遠方環境 {
        Some(入力) => ヘッダの間接照明::遠方環境の太陽方向(入力.太陽方向()),
        None => ヘッダの間接照明::定数近似の係数(環境光.値()),
    };
    let 方向光一覧 = [方向光レコード内容::方向光入力から写す(
        *方向光,
        照明.直接影().方向光の可視性(),
    )];
    let 局所光一覧 = 局所光の並びへ写す(局所光源列, 視点)?;
    Ok(照明問い合わせの書き込み内容 {
        ヘッダ: 照明問い合わせヘッダ内容 {
            方向光件数: 件数にする(方向光一覧.len()),
            局所光件数: 件数にする(局所光一覧.件数()),
            照明が有効か: 照明.有効性().有効か(),
            間接照明,
            クラスタ写像,
        },
        方向光一覧,
        局所光一覧,
    })
}

/// 世界が宣言した局所光を、宣言の順のままGPUのレコードの並びへ写す。件数が容量を超えないことは
/// 局所光源列の生成が既に保証しており、ここでの積み込みの失敗は到達しない経路の型付きの表明である。
fn 局所光の並びへ写す(
    局所光源列: &局所光源列, 視点: &描画視点
) -> Result<局所光レコードの並び, レンダラーエラー> {
    let mut 並び = 局所光レコードの並び::空で始める();
    for 点光源 in 局所光源列.点光源を宣言の順に返す() {
        並び.局所光レコードを末尾へ積む(局所光レコード内容::点光として写す(
            大域位置をgpu境界配列にする(点光源.位置(), 視点.カメラ大域原点())?,
            点光源.色(),
            点光源.強度(),
            点光源.影響半径(),
        ))?;
    }
    Ok(並び)
}

/// 件数は容量以下であることを梱包が確かめるため、ここで型付きの失敗にはしない。
/// 容量がu32へ収まらない値になることは無いが、収まらないなら梱包が件数不整合として落とす。
fn 件数にする(レコード数: usize) -> u32 {
    u32::try_from(レコード数).unwrap_or(u32::MAX)
}

/// GPU境界(生型境界): カメラ大域原点を引いてからf32の生値へ戻す。f64での減算が精度を守る唯一の境界である
/// (数学DDD。参照: CLAUDE.md「型安全性」)。
fn 大域位置をgpu境界配列にする(
    位置: 大域ワールド位置, カメラ大域原点: 大域ワールド位置
) -> Result<[f32; 3], レンダラーエラー> {
    let 相対 = 位置.カメラ相対へ変換する(カメラ大域原点)?;
    Ok([相対.x().値(), 相対.y().値(), 相対.z().値()])
}
