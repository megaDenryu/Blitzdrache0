//! ベンチ時だけ有効にするレンダラーCPU区間計測。Vulkan呼び出しの待機位置と、提示までの内訳を切り分ける。
//! 1フレームの境界を刻む時計は`clock`、ウォームアップ後の標本を貯める側は`store`にある。

#[cfg(test)]
mod cpu_timing_tests;

mod clock;
mod store;

pub(super) use clock::CPU区間時計;
pub(super) use store::CPU区間計測;

/// 1フレームのレンダラーCPU区間時間。終了時の診断ログへ渡す安全な計測値である。
/// `作業領域更新ms`と`描画記録送信提示ms`は`記録送信提示ms`の内訳であり、残差はUI入力の組み立てと読み戻しバッファの確保にあたる。
/// `作業領域更新ms`は可視ID列のGPUバッファへの書き込みと全個体の並べ替え検査を含み、物量に比例して増えうるため、記録・送信・提示の合計と分けて見る。
/// `描画記録送信提示ms`は、直接インスタンス描画では記録の量が個体数でなく発行数に比例するため、
/// この区間が物量で増えるかどうかが間接描画へ進む判断の根拠になる(参照: `_doc/設計/植生インスタンスと物量計測.md`「描画発行」)。
#[derive(Clone, Copy)]
pub struct CPU区間時間 {
    pub フェンス待機ms: f64,
    pub フレームデータ準備ms: f64,
    pub 画像取得ms: f64,
    pub 記録送信提示ms: f64,     // 画像取得の終わりから提示までの合計
    pub 作業領域更新ms: f64,     // 描画入力の作業領域を積み直した時間
    pub 描画記録送信提示ms: f64, // コマンドの記録と、送信と提示
}
