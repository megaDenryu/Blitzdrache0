//! フレームユニフォームへ書き込む内容の組み立てとGPUへの反映(判断24)。
//! 呼び出しタイミング: `draw_execute/prepare.rs`がフレームスロットのフェンス待ち後に呼ぶ
//! (前回のGPU使用完了後であることが保証される)。
//! 影の帯ごとのライトビュー射影・点光源位置・カメラ位置は焼いた値でなく、毎フレームここでカメラ大域原点を引いて組み立てる。
//! 不変条件: このフレームのGPU入力はすべて同じカメラ大域原点の相対フレームで表す(参照: `_doc/設計/地形とカメラ相対描画.md`)。

use blitz_math::大域ワールド位置;

use super::レンダラー;
use crate::cascade::{カスケード一式, 帯数, 帯番号};
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::view_input::描画視点;
use crate::vulkan::sync::フレームスロット添字;
use crate::vulkan::uniform::フレームユニフォーム内容;

impl レンダラー {
    pub(super) fn ユニフォームを書き込む(
        &self,
        フレーム添字: フレームスロット添字,
        入力: &フレーム描画入力<'_>,
        視点: &描画視点,
        ビュー射影行列: &[[f32; 4]; 4],
    ) -> Result<(), レンダラーエラー> {
        let 方向光 = 入力.ライティング.方向光();
        let 点光源 = 入力.ライティング.点光源();
        let 原点 = 視点.カメラ大域原点();
        let カスケード = 入力.ライティング.カスケードを組み立てる(原点, 視点.ビュー射影())?;
        let 内容 = フレームユニフォーム内容 {
            帯ライトビュー射影行列: 帯ごとの行列を作る(&カスケード, 原点)?,
            ビュー射影行列: *ビュー射影行列,
            カメラ相対位置: 大域位置をgpu境界配列にする(視点.カメラ大域位置(), 原点)?,
            方向光方向: 方向光.方向(),
            方向光色: 方向光.色(),
            方向光強度: 方向光.強度(),
            点光源位置: 大域位置をgpu境界配列にする(点光源.位置(), 原点)?,
            点光源色: 点光源.色(),
            点光源強度: 点光源.強度(),
            環境光係数: 入力.ライティング.環境光().値(),
            ライティング有効: 入力.ライティング.有効か(),
            影を落とす: 入力.ライティング.影を落とすか(),
            帯分割深度: カスケード.分割深度().map(|深度| 深度.値()),
            帯遷移幅: カスケード.遷移幅().map(|幅| 幅.値()),
            カメラ前方: カスケード.カメラ前方(),
            カスケード帯を可視化する: 入力.カスケード帯を可視化する,
            空: self.空の区画を組み立てる(入力, 視点.ビュー射影())?,
        };
        self.ユニフォーム.書き込む(self.環境.device(), フレーム添字, &内容)
    }
}

/// 帯ごとのライトビュー射影を、シャドウ記録・シーンのPCF・ライト視錐台の導出が共有する1つの構築結果から取り出す。
fn 帯ごとの行列を作る(
    カスケード: &カスケード一式, 原点: 大域ワールド位置
) -> Result<[[[f32; 4]; 4]; 帯数], レンダラーエラー> {
    let mut 行列一覧 = [[[0.0_f32; 4]; 4]; 帯数];
    for 番号 in 帯番号::全帯() {
        行列一覧[番号.添字()] = カスケード.帯のライトビュー射影(番号, 原点)?.gpu境界用列優先配列();
    }
    Ok(行列一覧)
}

/// GPU境界(生型境界): カメラ大域原点を引いてからf32の生値へ戻す。f64での減算が精度を守る唯一の境界である
/// (数学DDD。参照: CLAUDE.md「型安全性」)。
fn 大域位置をgpu境界配列にする(
    位置: 大域ワールド位置, カメラ大域原点: 大域ワールド位置
) -> Result<[f32; 3], レンダラーエラー> {
    let 相対 = 位置.カメラ相対へ変換する(カメラ大域原点)?;
    Ok([相対.x().値(), 相対.y().値(), 相対.z().値()])
}
