//! そのフレームのシェーダー定数3本(ビュー定数・多段影定数・空パス定数)と、そのフレームスロットの
//! 照明問い合わせ資源をGPUへ反映する入口。
//! 呼び出しタイミング: `draw_execute/prepare.rs`がフレームスロットのフェンス待ち後に呼ぶ
//! (前回のGPU使用完了後であることが保証される)。
//!
//! 多段一式はビューと影の両方の材料になるためここで1度だけ組み立て、内容の組み立ては
//! `view_uniform_write`と`cascade_uniform_write`へ渡す。空パス定数は空段階を持つ構成でだけ書く。
//! 不変条件: このフレームのGPU入力はすべて同じカメラ大域原点の相対フレームで表す(参照: `_doc/設計/地形とカメラ相対描画.md`)。

use super::レンダラー;
use crate::clustered_lighting::{クラスタの奥行き範囲, クラスタ写像, クラスタ格子の分割数, 視野の半角の正接};
use crate::error::{レンダラーエラー, 照明問い合わせ梱包エラー};
use crate::extent::ウィンドウ寸法;
use crate::frame_input::フレーム描画入力;
use crate::frame_lighting::フレーム照明入力;
use crate::view_input::描画視点;
use crate::vulkan::sync::フレームスロット添字;

use super::view_uniform_write::ビュー射影の行列一式;

impl レンダラー {
    pub(super) fn シェーダー定数を書き込む(
        &self,
        フレーム添字: フレームスロット添字,
        入力: &フレーム描画入力<'_>,
        視点: &描画視点,
        行列一式: &ビュー射影の行列一式,
    ) -> Result<(), レンダラーエラー> {
        let 原点 = 視点.カメラ大域原点();
        // 多段の当てはめはずらし無しを読む。テクセルスナップの基準がずらしで動くと静止物の影が泳ぐ。
        let 多段 = 入力.ライティング.多段を組み立てる(原点, 視点.ビュー射影の組().ずらし無し())?;
        self.多段の解像度が資源と一致するか確かめる(&多段)?;
        let device = self.環境.device();
        // 公開の`ライティング入力`から分解形への変換はこの1回だけ行い、以降の梱包は分解形だけを受け取る。
        let 照明 = フレーム照明入力::ライティング入力から写す(&入力.ライティング);

        let ビュー内容 = super::view_uniform_write::組み立てる(視点, 行列一式, &多段)?;
        self.シェーダー定数.ビュー定数を書き込む(device, フレーム添字, &ビュー内容)?;

        let 影内容 = super::cascade_uniform_write::組み立てる(入力, &多段, 原点)?;
        self.シェーダー定数.多段影の定数を書き込む(device, フレーム添字, &影内容)?;

        // クラスタ写像は描画先の画面の寸法に連動する。スワップチェーンが実際に決めた寸法を正本にするのは、
        // 局所可視度の画像が同じ寸法に連動する既存の経路と同じ値を読むためである。
        let クラスタ写像 = クラスタ写像を組み立てる(視点, 描画先の寸法へ写す(self.提示.寸法()))?;
        let 照明内容 = super::lighting_query_write::組み立てる(&照明, 入力.遠方環境.as_ref(), 視点, クラスタ写像)?;
        self.照明問い合わせ資源
            .スロットへ書き込む(device, フレーム添字, &照明内容.ヘッダ, &照明内容.方向光一覧, &照明内容.局所光一覧)?;

        // 空は逆ビュー射影から視線を復元するため、ジオメトリを描くパスと同じずらし付きを読む。
        self.空パスの定数を書き込む(フレーム添字, 入力, 視点.ビュー射影の組().ずらし付き())
    }

    /// 多段の構築が使った一辺と、確保済みシャドウマップ資源の一辺の一致を確かめる。
    /// この2つは起動指定から作られる別々の経路で運ばれるため、型だけでは同じ値であることを保証できない。
    fn 多段の解像度が資源と一致するか確かめる(
        &self, 多段: &crate::cascade::多段一式
    ) -> Result<(), レンダラーエラー> {
        let 設定 = 多段.解像度().テクセル数();
        let 資源 = self.シャドウマップ.一辺().テクセル数();
        if 設定 == 資源 {
            return Ok(());
        }
        Err(crate::error::多段エラー::一辺解像度不一致 { 設定, 資源 }.into())
    }
}

/// GPU境界: スワップチェーンが報告した寸法をエンジンの寸法の型へ戻す。ゼロ寸法はスワップチェーンが持ちえないが、
/// それでも寸法を検証するのはクラスタ写像の生成であり、ここは値を運ぶだけである。
fn 描画先の寸法へ写す(寸法: ash::vk::Extent2D) -> ウィンドウ寸法 {
    ウィンドウ寸法::生成する(寸法.width, 寸法.height)
}

/// 奥行き範囲と視野の半角の正接を射影の復元から採るのは、深度から奥行きを戻す工程と同じ4つの量を正本にするためである。
/// 別々に持つと、同じフレームの中で「深度が表す奥行き」と「格子が刻む奥行き」が食い違う。
/// 分割数は実測で調整するまでの仮置きを1箇所から読む。
fn クラスタ写像を組み立てる(
    視点: &描画視点,
    画面の寸法: ウィンドウ寸法,
) -> Result<クラスタ写像, 照明問い合わせ梱包エラー> {
    let 射影 = 視点.射影の復元();
    let 奥行き範囲 = クラスタの奥行き範囲::生成する(射影.近クリップ(), 射影.遠クリップ())?;
    let 縦の正接 = 射影.縦視野角の半角の正接();
    let 正接 = 視野の半角の正接::生成する(縦の正接 * 射影.横縦比(), 縦の正接)?;
    let 分割数 = クラスタ格子の分割数::仮置きの分割数を返す();
    Ok(クラスタ写像::生成する(分割数, 画面の寸法, 奥行き範囲, 正接)?)
}
