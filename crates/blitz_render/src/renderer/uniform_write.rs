//! そのフレームのシェーダー定数3本(ビュー・シーンパス定数・多段影定数・空パス定数)をGPUへ反映する入口。
//! 呼び出しタイミング: `draw_execute/prepare.rs`がフレームスロットのフェンス待ち後に呼ぶ
//! (前回のGPU使用完了後であることが保証される)。
//!
//! 多段一式はビューと影の両方の材料になるためここで1度だけ組み立て、内容の組み立ては
//! `view_pass_uniform_write`と`cascade_uniform_write`へ渡す。空パス定数は空段階を持つ構成でだけ書く。
//! 不変条件: このフレームのGPU入力はすべて同じカメラ大域原点の相対フレームで表す(参照: `_doc/設計/地形とカメラ相対描画.md`)。

use super::レンダラー;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::view_input::描画視点;
use crate::vulkan::sync::フレームスロット添字;

impl レンダラー {
    pub(super) fn シェーダー定数を書き込む(
        &self,
        フレーム添字: フレームスロット添字,
        入力: &フレーム描画入力<'_>,
        視点: &描画視点,
        ビュー射影行列: &[[f32; 4]; 4],
    ) -> Result<(), レンダラーエラー> {
        let 原点 = 視点.カメラ大域原点();
        let 多段 = 入力.ライティング.多段を組み立てる(原点, 視点.ビュー射影())?;
        let device = self.環境.device();

        let ビュー内容 = super::view_pass_uniform_write::組み立てる(入力, 視点, ビュー射影行列, &多段)?;
        self.シェーダー定数
            .ビューとシーンパスの定数を書き込む(device, フレーム添字, &ビュー内容)?;

        let 影内容 = super::cascade_uniform_write::組み立てる(入力, &多段, 原点)?;
        self.シェーダー定数.多段影の定数を書き込む(device, フレーム添字, &影内容)?;

        self.空パスの定数を書き込む(フレーム添字, 入力, 視点.ビュー射影())
    }
}
