//! フレームユニフォームへ書き込む内容の組み立てとGPUへの反映(判断24)。
//! 呼び出しタイミング: `draw_execute/prepare.rs`がフレームスロットのフェンス待ち後に呼ぶ
//! (前回のGPU使用完了後であることが保証される)。

use blitz_math::{ワールド, 位置};

use super::レンダラー;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::view_input::描画視点;
use crate::vulkan::uniform::フレームユニフォーム内容;

impl レンダラー {
    pub(super) fn ユニフォームを書き込む(
        &self,
        フレーム添字: usize,
        入力: &フレーム描画入力,
        視点: &描画視点,
        ビュー射影行列: &[[f32; 4]; 4],
    ) -> Result<(), レンダラーエラー> {
        let 方向光 = 入力.ライティング.方向光();
        let 点光源 = 入力.ライティング.点光源();
        let 内容 = フレームユニフォーム内容 {
            ライトビュー射影行列: 入力.ライティング.影().ライトビュー射影().gpu境界用列優先配列(),
            ビュー射影行列: *ビュー射影行列,
            カメラワールド位置: 位置をgpu境界配列にする(視点.カメラ位置()),
            方向光方向: 方向光.方向(),
            方向光色: 方向光.色(),
            方向光強度: 方向光.強度(),
            点光源位置: 位置をgpu境界配列にする(点光源.位置()),
            点光源色: 点光源.色(),
            点光源強度: 点光源.強度(),
            環境光係数: 入力.ライティング.環境光().値(),
            ライティング有効: 入力.ライティング.有効か(),
        };
        self.ユニフォーム.書き込む(&self.device, フレーム添字, &内容)
    }
}

/// GPU境界(生型境界): フレーム型・単位型を外して生の[f32;3]へ戻す唯一の場所
/// (数学DDD。参照: CLAUDE.md「型安全性」)。
fn 位置をgpu境界配列にする(位置: 位置<ワールド>) -> [f32; 3] {
    [位置.x().値(), 位置.y().値(), 位置.z().値()]
}
