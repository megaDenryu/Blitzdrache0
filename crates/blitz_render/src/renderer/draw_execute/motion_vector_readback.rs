//! 動きベクトルの読み戻し。担当するのは、この対象を指定して1フレーム描画する公開エントリと、読み戻しバッファの中身を
//! 動きベクトル読み戻し画像へ開く変換である。触れるフィールドは`読み戻しバッファ`と`提示`と`環境`に限る。
//!
//! この画像を直に読む入口を置くのは、動きベクトルがどの検収入口の絵にも現れないためである。色にも深度にも影響しない
//! 出力が意図どおり書かれていることは、その画像そのものを読む以外に確かめる手立てが無い
//! (参照: `_doc/設計/時間再構成.md`「段割りと各段の完了条件」の段3a)。
//!
//! 前提: 読み戻しバッファの確保は`submit`が読み戻し対象に合わせて済ませる。

use super::super::レンダラー;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::readback_image::{動きベクトル読み戻し画像, 読み戻し結果};
use crate::vulkan;
use crate::vulkan::readback::読み戻し対象;

impl レンダラー {
    /// 1フレーム描画し、そのフレームのシーン描画と空のパスが書いた動きベクトルを読み戻す。
    pub fn 一フレーム描画して動きベクトルを読み戻す(
        &mut self,
        入力: フレーム描画入力<'_>,
    ) -> Result<読み戻し結果<動きベクトル読み戻し画像>, レンダラーエラー> {
        match self.フレームを実行する(入力, Some(読み戻し対象::動きベクトル))? {
            crate::draw_result::描画結果::見送った(理由) => Ok(読み戻し結果::見送った(理由)),
            crate::draw_result::描画結果::提示した => {
                Ok(読み戻し結果::読み戻した(self.読み戻しバッファから動きベクトル画像を作る()?))
            }
        }
    }

    /// 提示成功直後に読み戻しバッファをホストから読み、動きベクトル画像へ変換する。
    fn 読み戻しバッファから動きベクトル画像を作る(
        &self,
    ) -> Result<動きベクトル読み戻し画像, レンダラーエラー> {
        vulkan::readback::動きベクトルを読み取る(self.環境.device(), self.確保済みの読み戻しバッファ(), self.提示.寸法())
    }
}
