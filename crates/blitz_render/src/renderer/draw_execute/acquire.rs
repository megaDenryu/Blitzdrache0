//! 次の提示画像を取得し、取得できた画像のハンドルを束ねる。取得が報告した陳腐化は提示状態へその場で反映する。

use ash::vk;

use super::super::cpu_timing::CPU区間時計;
use super::super::presentation::取得済み提示;
use super::super::レンダラー;
use crate::error::レンダラーエラー;
use crate::vulkan;
use crate::vulkan::frame::取得結果;

/// 提示状態へ反映する前の取得の事実。反映は`実行する`が行う。
enum 取得結末 {
    束ねた { 取得済み: 取得済み提示, 劣化: bool },
    再構築へ,
}

pub(super) fn 実行する(
    レンダラー: &mut レンダラー,
    取得セマフォ: vk::Semaphore,
    cpu区間時計: &mut Option<CPU区間時計>,
) -> Result<Option<取得済み提示>, レンダラーエラー> {
    let 結末 = 取得して束ねる(レンダラー, 取得セマフォ)?;
    if let Some(時計) = cpu区間時計 {
        時計.画像取得を終了する();
    }
    match 結末 {
        取得結末::束ねた { 取得済み, 劣化 } => {
            // 注意: サブオプティマルの反映をフレームの結末まで遅らせてはならない。送信が`Err`で戻る経路でこの観測が失われる。
            if 劣化 {
                レンダラー.提示.陳腐化した();
            }
            Ok(Some(取得済み))
        }
        取得結末::再構築へ => {
            レンダラー.提示.陳腐化した();
            Ok(None)
        }
    }
}

/// 通行証のもとで画像を取得し、取得できたらその添字ぶんのハンドルを読み出す。
/// 通行証を得られない状態は呼び出し元が描画可能を確かめた後であるため到達しないが、到達不能を型で示せないため再構築へ倒す。
fn 取得して束ねる(レンダラー: &レンダラー, 取得セマフォ: vk::Semaphore) -> Result<取得結末, レンダラーエラー> {
    let Some(許可) = レンダラー.提示.描画許可() else {
        return Ok(取得結末::再構築へ);
    };
    let 結果 = vulkan::frame::acquire::取得する(レンダラー.環境.swapchain_loader(), 許可.スワップチェーンハンドル(), 取得セマフォ)?;
    match 結果 {
        取得結果::取得した { 添字, 劣化 } => Ok(取得結末::束ねた {
            取得済み: 許可.取得した画像を束ねる(添字),
            劣化,
        }),
        取得結果::再構築が必要 => Ok(取得結末::再構築へ),
    }
}
