//! 局所可視度の読み戻し。担当するのは、この対象を指定して1フレーム描画する公開エントリと、読み戻しバッファの中身を局所可視度読み戻し画像へ開く変換である。
//! 触れるフィールドは`読み戻しバッファ`と`提示`と`環境`に限る。
//!
//! 最終色でなくこの画像を読むのは、拡散間接照度へ掛かる前の係数そのものをCPU正本と突き合わせるためである。
//! 最終色から逆算すると材質の取り分と間接照明の値が混ざり、slang写しの誤りだけを取り出せない
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「IIaの実装設計」)。
//!
//! 前提: 読み戻しバッファの確保は`submit`が読み戻し対象に合わせて済ませる。局所可視性補正のパスを積まないフレームで
//! この対象を要求することは呼び出し規律の破れであり、グラフの積み上げがpanicで落とす。

use super::super::レンダラー;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::readback_image::局所可視度読み戻し画像;
use crate::readback_image::読み戻し結果;
use crate::vulkan::readback::読み戻し対象;

impl レンダラー {
    /// 1フレーム描画し、そのフレームの両側ぼかしが書いた局所可視度を読み戻す。
    pub fn 一フレーム描画して局所可視度を読み戻す(
        &mut self,
        入力: フレーム描画入力<'_>,
    ) -> Result<読み戻し結果<局所可視度読み戻し画像>, レンダラーエラー> {
        match self.フレームを実行する(入力, Some(読み戻し対象::局所可視度))? {
            crate::draw_result::描画結果::見送った(理由) => Ok(読み戻し結果::見送った(理由)),
            crate::draw_result::描画結果::提示した => {
                Ok(読み戻し結果::読み戻した(self.読み戻しバッファから局所可視度画像を作る()?))
            }
        }
    }

    /// 提示成功直後に読み戻しバッファをホストから読み、局所可視度画像へ変換する。
    fn 読み戻しバッファから局所可視度画像を作る(&self) -> Result<局所可視度読み戻し画像, レンダラーエラー> {
        self.読み戻し画像の読み出し元().局所可視度の画像として開く()
    }
}
