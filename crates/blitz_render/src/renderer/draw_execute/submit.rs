//! 取得済み画像へ描画を記録・送信し、計測値とフレーム状態を更新する。

use super::super::presentation::取得済み提示;
use super::super::レンダラー;
use super::prepare::描画準備;
use crate::draw_result::描画結果;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::vulkan::readback::読み戻し対象;

pub(super) fn 実行する(
    レンダラー: &mut レンダラー,
    入力: フレーム描画入力<'_>,
    読み戻し要求: Option<読み戻し対象>,
    準備: 描画準備,
    取得済み: 取得済み提示,
) -> Result<描画結果, レンダラーエラー> {
    let 描画準備 {
        mut cpu区間時計,
        スロット資源,
    } = 準備;
    if let Some(対象) = 読み戻し要求 {
        if !レンダラー.提示.読み戻し対応() {
            return Err(レンダラーエラー::読み戻し非対応);
        }
        レンダラー.読み戻しバッファを確保する(対象)?;
    }
    let ui入力 = レンダラー.ui描画入力を組み立てる(スロット資源.スロット, 入力.ui描画.as_ref())?;
    // 注意: ここでフェンスを無信号化しない。以降の準備(資源表世代の作り直し・作業領域の充填・記録)はどれも失敗しうるため、
    // 送信へ到達しないまま無信号のフェンスが残ると、次に同じスロットを使うフレームの待機が永久に返らない。
    // 無信号化はキューへの送信の直前で行う(参照: `crates/blitz_render/src/vulkan/frame/submit_present.rs`)。
    let カメラ大域原点 = 入力.視点一覧.先頭().カメラ大域原点();
    let (提示劣化, 実績) = レンダラー.現在の画像で描画する(
        &取得済み,
        &スロット資源,
        cpu区間時計.as_mut(),
        &入力,
        入力.クリア色,
        入力.露出,
        読み戻し要求,
        ui入力.as_ref(),
        カメラ大域原点,
        入力.地形詳細段選択一覧,
        入力.可視個体選択一覧,
        入力.プリミティブ発行,
    )?;
    レンダラー
        .生成パス数の記録
        .大気のベイク済み画像
        .記録する(実績.大気のベイク済み画像生成パス数);
    レンダラー.生成パス数の記録.間接照明.記録する(実績.間接照明生成パス数);
    if let Some(計測) = &mut レンダラー.gpu計測 {
        計測.直近マッピングを記録する(スロット資源.スロット, 実績.計測マッピング);
    }
    if let (Some(時計), Some(計測)) = (cpu区間時計, &mut レンダラー.cpu区間計測) {
        計測.記録する(時計.終了する());
    }
    // 注意: 提示が報告した劣化はここで反映する。取得時の反映と同じく、フレームの結末までまとめて遅らせると`Err`経路で観測が失われる。
    if 提示劣化 {
        レンダラー.提示.陳腐化した();
    }
    Ok(描画結果::提示した)
}
