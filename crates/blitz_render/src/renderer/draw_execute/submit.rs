//! 取得済み画像へ描画を記録・送信し、計測値とフレーム状態を更新する。

use super::super::presentation::取得済み提示;
use super::super::レンダラー;
use super::prepare::描画準備;
use crate::draw_result::描画結果;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;

pub(super) fn 実行する(
    レンダラー: &mut レンダラー,
    入力: フレーム描画入力<'_>,
    読み戻し要求: bool,
    準備: 描画準備,
    取得済み: 取得済み提示,
) -> Result<描画結果, レンダラーエラー> {
    let 描画準備 {
        mut cpu区間時計,
        スロット資源,
    } = 準備;
    if 読み戻し要求 {
        if !レンダラー.提示.読み戻し対応() {
            return Err(レンダラーエラー::読み戻し非対応);
        }
        レンダラー.読み戻しバッファを確保する()?;
    }
    let ui入力 = レンダラー.ui描画入力を組み立てる(スロット資源.スロット, 入力.ui描画.as_ref())?;
    // 安全性: 送信前に失敗しうる読み戻し確保とUI入力構築を完了している。取得失敗時はこの関数へ到達しない。
    unsafe { レンダラー.環境.device().reset_fences(&[スロット資源.フェンス])? };
    let 布介入件数 = 入力.布.as_ref().map_or(0, |布| 布.介入件数);
    let カメラ大域原点 = 入力.視点一覧.先頭().カメラ大域原点();
    let (提示劣化, 実績) = レンダラー.現在の画像で描画する(
        &取得済み,
        &スロット資源,
        cpu区間時計.as_mut(),
        &入力,
        入力.クリア色,
        入力.露出,
        布介入件数,
        読み戻し要求,
        ui入力.as_ref(),
        カメラ大域原点,
        入力.地形詳細段選択一覧,
        入力.可視個体選択一覧,
    )?;
    レンダラー.大気のベイク済み画像生成計数.記録する(実績.大気のベイク済み画像生成パス数);
    if let Some(計測) = &mut レンダラー.gpu計測 {
        計測.直近マッピングを記録する(スロット資源.スロット, 実績.計測マッピング);
    }
    if let (Some(時計), Some(計測)) = (cpu区間時計, &mut レンダラー.cpu区間計測) {
        計測.記録する(時計.終了する());
    }
    // 注意: 提示が報告した劣化はここで反映する。取得時の反映と同じく、フレームの結末までまとめて遅らせると`Err`経路で観測が失われる。
    if 提示劣化 {
        レンダラー.提示.陳腐化した();
    }
    Ok(描画結果::提示した)
}
