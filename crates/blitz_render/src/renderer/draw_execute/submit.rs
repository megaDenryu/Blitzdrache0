//! 取得済み画像へ描画を記録・送信し、計測値とフレーム状態を更新する。

use super::super::レンダラー;
use super::prepare::描画準備;
use crate::draw_result::描画結果;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;

pub(super) fn 実行する(
    レンダラー: &mut レンダラー,
    入力: フレーム描画入力,
    読み戻し要求: bool,
    準備: 描画準備,
    画像添字: u32,
) -> Result<描画結果, レンダラーエラー> {
    if 読み戻し要求 {
        if !レンダラー.swapchain.読み戻し対応 {
            return Err(レンダラーエラー::読み戻し非対応);
        }
        レンダラー.読み戻しバッファを確保する()?;
    }
    let ui入力 = レンダラー.ui描画入力を組み立てる(準備.スロット資源.スロット, 入力.ui描画.as_ref())?;
    // 安全性: 送信前に失敗しうる読み戻し確保とUI入力構築を完了している。取得失敗時はこの関数へ到達しない。
    unsafe { レンダラー.環境.device().reset_fences(&[準備.スロット資源.フェンス])? };
    let 布介入件数 = 入力.布.as_ref().map_or(0, |布| 布.介入件数);
    let (提示劣化, 計測マッピング) = レンダラー.現在の画像で描画する(
        画像添字,
        &準備.スロット資源,
        入力.クリア色,
        入力.露出,
        布介入件数,
        読み戻し要求,
        ui入力.as_ref(),
    )?;
    if let Some(計測) = &mut レンダラー.gpu計測 {
        計測.直近マッピングを記録する(準備.スロット資源.スロット, 計測マッピング);
    }
    if let (Some(時計), Some(計測)) = (準備.cpu区間時計, &mut レンダラー.cpu区間計測) {
        計測.記録する(時計.終了する());
    }
    レンダラー.再構築が必要 |= 提示劣化;
    Ok(描画結果::提示した)
}
