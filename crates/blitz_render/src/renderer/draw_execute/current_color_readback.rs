//! 時間再構成のパスが読む前の、シーン・空・粒子が描いた色の読み戻し。担当するのは、この対象を指定して1フレーム描画する
//! 公開エントリと、読み戻しバッファの中身をHDR読み戻し画像へ開く変換である。触れるフィールドは`読み戻しバッファ`と`提示`と`環境`に限る。
//!
//! 圧縮前のHDRと別の入口を置くのは、時間再構成のパスを積むフレームでは圧縮前のHDRが再構成の出力になるためである。
//! 「履歴を無効にした直後の1フレーム目の結果が今のフレームの色と一致する」ことを画素で見る検収は、突き合わせる
//! 2枚を別の画像から採らなければ成立しない(`参照: _doc/設計/時間再構成.md`「検収戦略(判断g)」の4)。
//!
//! 前提: 読み戻しバッファの確保は`submit`が読み戻し対象に合わせて済ませる。

use super::super::レンダラー;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::readback_image::{HDR読み戻し画像, 読み戻し結果};
use crate::vulkan::readback::読み戻し対象;

impl レンダラー {
    /// 1フレーム描画し、時間再構成のパスが読んだ今のフレームの色を読み戻す。
    /// 時間再構成のパスを積まないフレームでこれを呼ぶのは配線の誤りであり、グラフの積み上げがpanicで検出する。
    pub fn 一フレーム描画して今のフレームの色を読み戻す(
        &mut self,
        入力: フレーム描画入力<'_>,
    ) -> Result<読み戻し結果<HDR読み戻し画像>, レンダラーエラー> {
        match self.フレームを実行する(入力, Some(読み戻し対象::今のフレームの色))? {
            crate::draw_result::描画結果::見送った(理由) => Ok(読み戻し結果::見送った(理由)),
            crate::draw_result::描画結果::提示した => {
                Ok(読み戻し結果::読み戻した(self.読み戻しバッファから今のフレームの色を作る()?))
            }
        }
    }

    /// 提示成功直後に読み戻しバッファをホストから読み、今のフレームの色へ変換する。
    fn 読み戻しバッファから今のフレームの色を作る(&self) -> Result<HDR読み戻し画像, レンダラーエラー> {
        self.読み戻し画像の読み出し元()
            .半精度四成分の画像として開く(読み戻し対象::今のフレームの色)
    }
}
