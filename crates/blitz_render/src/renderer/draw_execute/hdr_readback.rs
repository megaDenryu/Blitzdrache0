//! 明るさの圧縮を通す前のHDR中間画像の読み戻し。担当するのは、この対象を指定して1フレーム描画する公開エントリと、読み戻しバッファの中身をHDR読み戻し画像へ開く変換である。触れるフィールドは`読み戻しバッファ`と`提示`と`環境`に限る。
//!
//! 提示画像の読み戻し(`draw_execute`と`readback_buffer`)と別に置くのは、1画素あたりのバイト数も成分の型も違い、8ビットの並びを前提に書かれた提示側の変換をそのまま使えないためである。
//! この対象を読むのは、絵の見え方でなく放射輝度そのものを測る検収だけである。
//!
//! 前提: 読み戻しバッファの確保は`submit`が読み戻し対象に合わせて済ませる。

use super::super::レンダラー;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::readback_image::HDR読み戻し画像;
use crate::readback_image::読み戻し結果;
use crate::vulkan::readback::読み戻し対象;

impl レンダラー {
    /// 1フレーム描画し、明るさの圧縮を通す前のHDR中間画像を読み戻す。露出倍率を掛ける前の値を持つため、絵の見え方に依らない輝度の統計はこの結果から採る。
    pub fn 一フレーム描画して圧縮前のhdrを読み戻す(
        &mut self,
        入力: フレーム描画入力<'_>,
    ) -> Result<読み戻し結果<HDR読み戻し画像>, レンダラーエラー> {
        match self.フレームを実行する(入力, Some(読み戻し対象::圧縮前のHDR))? {
            crate::draw_result::描画結果::見送った(理由) => Ok(読み戻し結果::見送った(理由)),
            crate::draw_result::描画結果::提示した => Ok(読み戻し結果::読み戻した(self.読み戻しバッファからhdr画像を作る()?)),
        }
    }

    /// 提示成功直後に読み戻しバッファをホストから読み、圧縮前のHDR中間画像へ変換する。
    fn 読み戻しバッファからhdr画像を作る(&self) -> Result<HDR読み戻し画像, レンダラーエラー> {
        self.読み戻し画像の読み出し元().半精度四成分の画像として開く(読み戻し対象::圧縮前のHDR)
    }
}
