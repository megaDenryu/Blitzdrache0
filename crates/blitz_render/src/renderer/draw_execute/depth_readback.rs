//! 最終深度の読み戻し。担当するのは、この対象を指定して1フレーム描画する公開エントリと、読み戻しバッファの中身を深度読み戻し画像へ開く変換である。
//! 触れるフィールドは`読み戻しバッファ`と`提示`と`環境`に限る。
//!
//! 提示画像・圧縮前のHDRと別に置くのは、1画素あたりのバイト数も成分の意味も違うためである。
//! この対象を読むのは、深度プリパスの三条件が同じ深度を作ったかどうかを色と別に判定する検収だけである
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「IIaの実装設計」)。
//!
//! 前提: 読み戻しバッファの確保は`submit`が読み戻し対象に合わせて済ませる。

use super::super::レンダラー;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::readback_image::深度読み戻し画像;
use crate::readback_image::読み戻し結果;
use crate::vulkan::readback::読み戻し対象;

impl レンダラー {
    /// 1フレーム描画し、そのフレームの全パスが書き終えた後の深度を読み戻す。
    pub fn 一フレーム描画して最終深度を読み戻す(
        &mut self,
        入力: フレーム描画入力<'_>,
    ) -> Result<読み戻し結果<深度読み戻し画像>, レンダラーエラー> {
        match self.フレームを実行する(入力, Some(読み戻し対象::最終深度))? {
            crate::draw_result::描画結果::見送った(理由) => Ok(読み戻し結果::見送った(理由)),
            crate::draw_result::描画結果::提示した => Ok(読み戻し結果::読み戻した(self.読み戻しバッファから深度画像を作る()?)),
        }
    }

    /// 提示成功直後に読み戻しバッファをホストから読み、最終深度画像へ変換する。
    fn 読み戻しバッファから深度画像を作る(&self) -> Result<深度読み戻し画像, レンダラーエラー> {
        self.読み戻し画像の読み出し元().深度画像として開く()
    }
}
