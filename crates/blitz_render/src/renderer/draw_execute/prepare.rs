//! フェンス待機後にGPU計測を読み、退役してよくなった資源表世代を回収し、フレーム固有バッファを書き込む。
//!
//! 資源表世代の回収をここへ置くのは、フェンスの通過を知る唯一の地点だからである。通過を記録しないと台帳は
//! そのスロットが世代を保持し続けていると見なし、旧世代を永久に退役させられない。

use super::super::cpu_timing::CPU区間時計;
use super::super::frame_progress::フレームスロット資源;
use super::super::view_uniform_write::ビュー射影の行列一式;
use super::super::レンダラー;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::view_input::描画視点;
use crate::vulkan::material_table::材質資源の作業環境;
use crate::vulkan::sync::フレームスロット添字;
use crate::vulkan::transfer::ステージング経由の転送係;

/// 誰も保持しなくなった資源表世代の資源をここで返す。フェンスの通過を知る唯一の地点であり、
/// 記録を怠ると台帳はそのスロットが世代を保持し続けていると見なす。
fn 資源表世代のフェンス通過を記録する(レンダラー: &mut レンダラー, スロット: フレームスロット添字) {
    let 確保係 = レンダラー.gpu環境.資源の確保係を貸す();
    let 作業環境 = 材質資源の作業環境 {
        問い合わせ: レンダラー.gpu環境.物理デバイス問い合わせ(),
        転送係: ステージング経由の転送係::生成する(&確保係, &レンダラー.転送環境),
        セットレイアウト: &レンダラー.セットレイアウト,
    };
    レンダラー.材質資源表.フェンス通過を記録して退役させる(作業環境, スロット);
}

pub(super) struct 描画準備 {
    pub(super) cpu区間時計: Option<CPU区間時計>,
    pub(super) スロット資源: フレームスロット資源,
}

pub(super) fn 実行する(
    レンダラー: &mut レンダラー,
    入力: &フレーム描画入力<'_>,
    視点: &描画視点,
    行列一式: &ビュー射影の行列一式,
) -> Result<描画準備, レンダラーエラー> {
    let mut cpu区間時計 = レンダラー.cpu区間計測.as_ref().map(|_| CPU区間時計::開始する());
    let スロット資源 = レンダラー.フレーム進行.現在のスロット資源();
    let フレーム添字 = スロット資源.スロット;
    // 安全性: フェンスは前フレームまたは初期シグナル状態のGPU完了を表す。
    unsafe { レンダラー.gpu環境.device().wait_for_fences(&[スロット資源.フェンス], true, u64::MAX)? };
    if let Some(時計) = &mut cpu区間時計 {
        時計.フェンス待機を終了する();
    }
    if let Some(計測) = &mut レンダラー.gpu計測 {
        計測.読み取る(レンダラー.gpu環境.device(), フレーム添字);
    }
    資源表世代のフェンス通過を記録する(レンダラー, フレーム添字);
    レンダラー.大気媒体を書き込む(フレーム添字, 入力)?;
    レンダラー.シェーダー定数を書き込む(フレーム添字, 入力, 視点, 行列一式)?;
    レンダラー.スキン行列を書き込む(フレーム添字, 入力)?;
    レンダラー.布フレームを書き込む(フレーム添字, 入力)?;
    if let Some(時計) = &mut cpu区間時計 {
        時計.フレームデータ準備を終了する();
    }
    Ok(描画準備 {
        cpu区間時計, スロット資源
    })
}
