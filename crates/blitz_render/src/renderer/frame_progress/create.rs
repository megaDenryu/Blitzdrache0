//! フレーム進行が保つ資源の確保。コマンドプールとコマンドバッファ、フレームごとの同期物をここでまとめて作り、スロット巡回を先頭から始める。
//! 途中で失敗したときに確保済みのコマンドプールを解放する経路をここへ閉じるため、この型が自分の一部を漏らすことはない。

use ash::vk;

use super::slot_cycle::フレームスロット巡回;
use super::フレーム進行;
use crate::error::レンダラーエラー;
use crate::vulkan;
use crate::vulkan::allocator::GPU資源の確保係;
use crate::vulkan::frame::フレームの記録の実行環境;

impl フレーム進行 {
    pub(in crate::renderer) fn 生成する(
        確保係: &GPU資源の確保係<'_>,
        キューファミリ添字: u32,
        queue: vk::Queue,
    ) -> Result<Self, レンダラーエラー> {
        let コマンド一式 = 確保係.フレーム記録のコマンド一式を確保する(キューファミリ添字)?;
        let フレーム同期 = match vulkan::sync::フレーム同期::生成する(確保係.論理デバイス()) {
            Ok(値) => 値,
            Err(誤り) => {
                コマンド一式.破棄する(確保係.論理デバイス());
                return Err(誤り);
            }
        };
        Ok(Self {
            コマンド一式,
            記録の実行環境: フレームの記録の実行環境::生成する(確保係.論理デバイス(), queue),
            フレーム同期,
            巡回: フレームスロット巡回::先頭から始める(),
            見送り累計: 0,
        })
    }
}
