//! フレームスロットを進めるかどうかの規則。提示まで到達したフレームだけがスロットを1つ進め、見送ったフレームは同じスロットを次フレームへ残す。
//! 注意: 見送りでスロットを進めると、送信していないフェンスを待つことになり待機が返らない。逆に提示で進め損ねると、GPUが使用中のスロットのコマンドバッファを上書きする。
//! GPUを必要としない値の計算だけで閉じているため、この規則はユニットテストで確かめられる。

#[cfg(test)]
mod slot_cycle_tests;

use crate::draw_result::描画結果;
use crate::vulkan::sync::フレームスロット添字;

/// 1フレームの結末。スロットを進めるかどうかはこの2択だけで決まる。
///
/// `提示した`はスワップチェーンへ提示した結末であり、このスロットのフェンスにはGPUへ送信済みの作業が結び付いている。
/// `見送った`は提示へ到達しなかった結末であり、このスロットのフェンスは送信されていないため、次フレームが同じスロットを使う。
#[derive(Clone, Copy)]
pub(in crate::renderer) enum フレーム結末 {
    提示した,
    見送った,
}

impl フレーム結末 {
    /// 描画の結果から結末を決める。失敗(`Err`)は`?`で戻るためこの判定へ到達せず、スロットは据え置かれる。
    /// 送信済みのフェンスが無いスロットを次フレームがそのまま使い直せる状態にするための規律である。
    pub(in crate::renderer) fn 描画結果から判定する(結果: 描画結果) -> Self {
        match 結果 {
            描画結果::提示した => Self::提示した,
            描画結果::見送った(_) => Self::見送った,
        }
    }
}

/// 毎フレームの描画経路で使うフレームスロット添字は、この巡回だけが発生源になる。
pub(super) struct フレームスロット巡回 {
    現在: フレームスロット添字,
}

impl フレームスロット巡回 {
    pub(super) const fn 先頭から始める() -> Self {
        Self {
            現在: フレームスロット添字::先頭(),
        }
    }

    pub(super) const fn 現在のスロット(&self) -> フレームスロット添字 {
        self.現在
    }

    pub(super) fn 結末を反映する(&mut self, 結末: フレーム結末) {
        match 結末 {
            フレーム結末::提示した => self.現在 = self.現在.次のスロット(),
            フレーム結末::見送った => {}
        }
    }
}
