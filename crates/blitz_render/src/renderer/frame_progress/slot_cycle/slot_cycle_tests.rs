use super::{フレームスロット巡回, フレーム結末};
use crate::vulkan::sync::フレームインフライト数;

#[test]
fn 先頭スロットから始まる() {
    assert_eq!(フレームスロット巡回::先頭から始める().現在のスロット(), 0);
}

#[test]
fn 提示したらスロットが1つ進む() {
    let mut 巡回 = フレームスロット巡回::先頭から始める();
    巡回.結末を反映する(フレーム結末::提示した);
    assert_eq!(巡回.現在のスロット(), 1);
}

#[test]
fn 見送ったらスロットは据え置かれる() {
    let mut 巡回 = フレームスロット巡回::先頭から始める();
    巡回.結末を反映する(フレーム結末::見送った);
    巡回.結末を反映する(フレーム結末::見送った);
    assert_eq!(巡回.現在のスロット(), 0);
}

#[test]
fn フレームインフライト数で巡回する() {
    let mut 巡回 = フレームスロット巡回::先頭から始める();
    for _ in 0..フレームインフライト数 {
        巡回.結末を反映する(フレーム結末::提示した);
    }
    assert_eq!(巡回.現在のスロット(), 0);
}

#[test]
fn 見送りを挟んでも提示の回数だけ進む() {
    let mut 巡回 = フレームスロット巡回::先頭から始める();
    巡回.結末を反映する(フレーム結末::見送った);
    巡回.結末を反映する(フレーム結末::提示した);
    巡回.結末を反映する(フレーム結末::見送った);
    assert_eq!(巡回.現在のスロット(), 1 % フレームインフライト数);
}

#[test]
fn 全スロットが一巡で1回ずつ現れる() {
    let mut 巡回 = フレームスロット巡回::先頭から始める();
    let mut 出現 = Vec::with_capacity(フレームインフライト数);
    for _ in 0..フレームインフライト数 {
        出現.push(巡回.現在のスロット());
        巡回.結末を反映する(フレーム結末::提示した);
    }
    出現.sort_unstable();
    assert_eq!(出現, (0..フレームインフライト数).collect::<Vec<_>>());
}
