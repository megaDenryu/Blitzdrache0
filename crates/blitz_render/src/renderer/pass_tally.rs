//! フレームごとに積んだ生成パスの本数の記録の束。担当するのは「大気のベイク済み画像と間接照明のそれぞれの記録を
//! 1つの器で保ち、レンダラー直下のフィールドを種類ごとに増やさない」ことである。
//!
//! 2つを別の記録にするのは、数える対象と期待する本数が違うためである。大気は表の枚数を1つの数で数え、
//! 間接照明はパスの種類ごとの内訳で数える。1つの数へ足し込むと、既存の検収が読んでいる大気の判定値が動く。

mod atmosphere;
mod indirect_lighting;

pub use atmosphere::大気のベイク済み画像生成パス数の記録;
pub use indirect_lighting::間接照明生成パス数の記録;

/// 2つの記録の束。
pub(super) struct 生成パス数の記録一式 {
    pub(super) 大気のベイク済み画像: 大気のベイク済み画像生成パス数の記録,
    pub(super) 間接照明: 間接照明生成パス数の記録,
}

impl 生成パス数の記録一式 {
    pub(super) fn 新規() -> Self {
        Self {
            大気のベイク済み画像: 大気のベイク済み画像生成パス数の記録::新規(),
            間接照明: 間接照明生成パス数の記録::新規(),
        }
    }
}
