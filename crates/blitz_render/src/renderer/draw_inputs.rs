//! ジオメトリ・シャドウ・粒子の描画入力の組み立て。
//! `draw_dispatch`の行数分割のためだけに切り出した内部ヘルパー。

use super::レンダラー;
use crate::vulkan::frame::{シャドウ描画入力, ジオメトリ入力, 粒子描画入力};

impl レンダラー {
    pub(super) fn 描画入力作業領域を更新する(&mut self, フレーム添字: usize) {
        self.ジオメトリ入力作業領域.clear();
        self.シャドウ入力作業領域.clear();
        for (添字, 資源) in self.描画対象資源一覧.iter().enumerate() {
            // スキニングはシーンの先頭対象だけへ適用する(判断44の既存契約)。
            let 頂点バッファ = if 添字 == 0 {
                self.スキニング.as_ref().map_or(資源.ジオメトリ.頂点バッファ, |一式| 一式.出力バッファ())
            } else {
                資源.ジオメトリ.頂点バッファ
            };
            let ディスクリプタセット = self.ディスクリプタ.set(添字, フレーム添字);
            self.ジオメトリ入力作業領域.push(ジオメトリ入力 {
                頂点バッファ,
                インデックスバッファ: 資源.ジオメトリ.インデックスバッファ,
                インデックス数: 資源.ジオメトリ.インデックス数,
                layout: self.pipeline.layout,
                ディスクリプタセット,
            });
            self.シャドウ入力作業領域.push(シャドウ描画入力 {
                pipeline: self.シャドウパイプライン.handle,
                layout: self.シャドウパイプライン.layout,
                頂点バッファ,
                インデックスバッファ: 資源.ジオメトリ.インデックスバッファ,
                インデックス数: 資源.ジオメトリ.インデックス数,
                ディスクリプタセット,
            });
        }
    }

    pub(super) fn 粒子描画入力を組み立てる(&self, フレーム添字: usize) -> Option<粒子描画入力> {
        self.粒子.as_ref().map(|粒子| 粒子描画入力 {
            コンピュートパイプライン: 粒子.コンピュートパイプライン.handle,
            コンピュートlayout: 粒子.コンピュートパイプライン.layout,
            描画パイプライン: 粒子.描画パイプライン.handle,
            描画layout: 粒子.描画パイプライン.layout,
            ディスクリプタセット: 粒子.ディスクリプタ.set(フレーム添字),
            バッファ: 粒子.バッファ.buffer,
            更新スレッド数: 粒子.更新スレッド数,
            描画要素数: 粒子.描画要素数,
        })
    }
}
