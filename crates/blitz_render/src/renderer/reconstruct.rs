//! レンダラーの外で起きた出来事の受け取りと、それに応じた資源の作り直し。ウィンドウ寸法の変更と、
//! カメラの視点を不連続に差し替えたことの2つがここへ届く。
//! 寸法変更は提示資源とポスト処理画像の再構築、および実表示計測への世代交代通知まで進む。
//! 通知が移した`陳腐化`を次フレームの再構築が`描画可能`へ戻す対であるため、要求と実行を同じ場所に置く。
//! 要求寸法の保持と状態の遷移は`presentation`が担うため、ここは真偽値も寸法も持たない。
//! スワップチェーン・深度バッファ・提示同期の3つは`提示`が揃って作り直すため、ここは束の外で
//! 寸法に追従する必要があるもの(ポスト処理の中間画像)と、世代が変わったことを知る必要があるもの(実表示計測)だけを扱う。
//! パイプラインは動的ビューポート/シザーのため再構築不要（判断8）。
//! フレームごとの同期物（フェンス・取得セマフォ）とコマンドバッファは
//! 再構築時に作り直さない（判断13）。

use super::レンダラー;
use crate::error::レンダラーエラー;
use crate::extent::{ウィンドウ寸法, 非ゼロ寸法};

impl レンダラー {
    /// ウィンドウの寸法変更を通知する。次フレームでスワップチェーンを再構築する。
    pub fn サイズ変更を通知する(&mut self, 寸法: ウィンドウ寸法) {
        self.提示.寸法変更を受ける(寸法);
    }

    /// カメラの視点を不連続に差し替えたことを通知する。次に描くフレームは履歴を1画素も混ぜず、
    /// 今のフレームの結果をそのまま出す。
    ///
    /// 判断cの無効化条件のうち、レンダラーの内側で検出できないのはこの1つだけである。スワップチェーンの
    /// 作り直しは下の再構築が、シェーダーとアセットの再読込は差し替えの入口が、それぞれ同じ無効化を呼ぶ。
    /// 履歴の零埋めと無効化を別物として置くのは、零埋めが非数対策だからである。確保したばかりの半精度の
    /// 不定ビット列は非数にもなりうるため零で埋めるが、その零を履歴の寄与率で混ぜると初回とリサイズ直後の
    /// 絵が暗転する。無効化はその1フレームだけ混合そのものを止める(`参照: _doc/設計/時間再構成.md`「判断c」)。
    pub fn 時間再構成の履歴を無効にする(&mut self) {
        self.時間再構成.履歴を無効にする();
    }

    /// 前提: 呼び出し元は`提示状態::陳腐化`から取り出した要求寸法を渡す。
    pub(super) fn スワップチェーンを再構築する(&mut self, 要求寸法: 非ゼロ寸法) -> Result<(), レンダラーエラー> {
        // 古い提示資源の破棄を含むため、作り直しの前にGPU使用完了を待つ。
        self.環境.gpuの全作業完了を待つ()?;
        self.提示.作り直す(&self.環境, 要求寸法)?;

        // ポスト処理の画像はスワップチェーン寸法に連動するため作り直す(判断38・41)。有無の判定はフレーム構成を再度読まず、
        // 一式そのものの有無で行う(生成時にフレーム構成から決めた結果と常に一致する)。
        let 新寸法 = self.提示.寸法();
        if let Some(ポスト処理) = self.ポスト処理.as_mut() {
            let メモリプロパティ = self.環境.メモリプロパティを取得する();
            ポスト処理.寸法に追従する(self.環境.device(), &メモリプロパティ, 新寸法)?;
        }
        // 局所可視度の2枚も画面寸法に連動する。作り直しの後に照明問い合わせのセットを結び直さないと、
        // 破棄済みのビューを指したままのセットで描くことになる。
        let メモリプロパティ = self.環境.メモリプロパティを取得する();
        self.局所可視性
            .寸法に追従する(self.環境.device(), &メモリプロパティ, &self.転送環境, 新寸法, self.提示.深度ビュー())?;
        self.照明問い合わせ資源
            .局所可視度の画像を結ぶ(self.環境.device(), self.局所可視性.ぼかし後のビュー());
        // 動きベクトルと履歴の3枚も画面寸法に連動する。作り直しは判断cの履歴の無効化条件の1つでもあり、前の寸法の履歴は引き継がない。
        self.時間再構成.寸法に追従する(
            self.環境.device(),
            &メモリプロパティ,
            &self.転送環境,
            crate::vulkan::temporal_reconstruction::画面の入力 {
                寸法: 新寸法,
                深度ビュー: self.提示.深度ビュー(),
            },
        )?;
        self.実表示計測.スワップチェーンを作り直した();
        Ok(())
    }
}
