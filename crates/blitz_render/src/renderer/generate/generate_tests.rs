use crate::error::{レンダラーエラー, 生成要求不一致エラー};
use crate::frame_composition::{フレームの処理位置, フレーム構成};

#[test]
fn 粒子素材に粒子の処理位置が無ければ拒否する() {
    let 構成結果 = フレーム構成::生成する(&[フレームの処理位置::影, フレームの処理位置::シーン]);
    let Ok(構成) = 構成結果 else {
        panic!("テスト用フレーム構成を生成できなかった");
    };

    let 結果 = super::構成と素材を検査する(&構成, false, false, true);
    assert!(matches!(結果, Err(レンダラーエラー::生成要求不一致(生成要求不一致エラー::フレーム構成素材不一致(フレームの処理位置::粒子)))));
}
