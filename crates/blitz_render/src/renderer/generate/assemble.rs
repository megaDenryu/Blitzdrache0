//! 生成済みのコア資源とフレーム資源をレンダラーの所有フィールドへ移す。

use super::core_setup::コア資源;
use super::frame_resources::フレーム資源;
use crate::frame_composition::フレーム構成;
use crate::renderer::レンダラー;

pub(super) fn レンダラーを組み立てる(
    コア: コア資源, 資源: フレーム資源, フレーム構成: フレーム構成
) -> レンダラー {
    レンダラー {
        環境: コア.環境,
        提示: コア.提示,
        シャドウマップ: 資源.シャドウマップ,
        転送環境: 資源.転送環境,
        シーン描画資源: 資源.シーン描画資源,
        ユニフォーム: 資源.ユニフォーム,
        フレーム進行: 資源.フレーム進行,
        フレーム構成,
        描画段階資源: 資源.描画段階資源,
        スキニング: 資源.スキニング,
        布: 資源.布,
        ポスト処理: 資源.ポスト処理,
        粒子: 資源.粒子,
        gpu計測: 資源.gpu計測,
        cpu区間計測: None,
        大気lutを焼いたか: false,
        大気lut生成計数: crate::renderer::大気LUT生成パス数の記録::新規(),
        実表示計測: コア.実表示計測,
        ui一式: 資源.ui一式,
        読み戻しバッファ: None,
        検証カウンタ: コア.検証カウンタ,
    }
}
