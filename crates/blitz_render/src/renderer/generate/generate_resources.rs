//! 提示側の資源の生成後に組み立てる残り資源の組み立て手順。段ごとの生成はサブモジュールへ分ける(基礎/パイプライン/粒子/ポスト処理/シミュレーション)。束の型は`frame_resources`。
//! 注意: パイプライン台帳は失敗しうる生成の最後に作る。台帳が持つのは生のパイプラインとパイプラインレイアウトであり、作った後に`?`で抜ける経路があるとその失敗で未破棄のまま落ちる。
//! GPU計測・開発用UI・フレーム進行はそれぞれ1つの生成呼び出しで済み、この手順が足す判断も条件も無いため、サブモジュールを設けずここに置く。

mod base_resources;
mod bundle;
mod cloth_resources;
mod particle_resources;
mod post_process_resources;
mod request;
mod simulation_resources;

use super::frame_resources::フレーム資源;
use crate::error::レンダラーエラー;
use crate::renderer::draw_stage_resources::{描画段階資源, 生成要求 as 描画段階資源生成要求};
use crate::renderer::frame_progress::フレーム進行;
use crate::vulkan;
use post_process_resources::描画先構成;

pub(in crate::renderer::generate) use request::生成要求;

pub(super) fn 組み立てる(要求: 生成要求<'_>) -> Result<フレーム資源, レンダラーエラー> {
    let 描画先 = 描画先構成::決める(要求.フレーム構成);
    let シーンカラー形式 = 描画先.シーンカラー形式(要求.提示.画像形式());
    let device = 要求.環境.device();

    let メモリプロパティ = 要求.環境.メモリプロパティを取得する();
    let 照明束縛 = vulkan::pipeline_ledger::照明束縛レイアウト::契約から選ぶ(要求.照明問い合わせ契約);
    let 基礎 = base_resources::組み立てる(要求.環境, &メモリプロパティ, 要求.描画シーン, 要求.影の一辺, 照明束縛)?;

    let フレーム進行 = フレーム進行::生成する(device, 要求.環境.キューファミリ添字())?;
    let 描画段階 = 描画段階資源::生成する(描画段階資源生成要求 {
        device,
        メモリプロパティ: &メモリプロパティ,
        シーンカラー形式,
        セットレイアウト: &基礎.セットレイアウト,
        シェーダー: 要求.シェーダー,
        構成: 要求.フレーム構成,
        照明問い合わせ契約: 要求.照明問い合わせ契約,
    })?;
    // 遠方環境の3つの画像は描画段階資源が持つため、束が組み上がった後で照明問い合わせのセットへ結ぶ。
    基礎.照明問い合わせ.遠方環境の画像を結ぶ(device, 描画段階.遠方環境の束縛先());
    let 粒子 = particle_resources::組み立てる(&要求, &メモリプロパティ, &基礎, シーンカラー形式)?;
    // 合成区間の中身はパス名を所有する層が決める。計器は宣言を適用するだけで、間接照明という機能を1つも知らない。
    let 合成区間一覧 = vec![
        vulkan::indirect_lighting::合成区間を宣言する(),
        vulkan::frame::record::pass_names::合成区間を宣言する(),
    ];
    let gpu計測 = vulkan::gpu_timing::パス別GPU計測::生成する(device, 要求.タイムスタンプ対応か, 要求.タイムスタンプ周期ns, 合成区間一覧)?;
    let ui一式 = vulkan::ui::UIリソース一式::生成する(device, 要求.提示.画像形式(), &要求.シェーダー.ui)?;
    let ポスト処理 = 描画先.組み立てる(device, &メモリプロパティ, 要求.提示, 要求.シェーダー, &基礎.転送環境, 要求.自動露出の設定)?;
    let (スキニング, 布) = simulation_resources::組み立てる(
        device,
        &メモリプロパティ,
        &基礎.転送環境,
        シーンカラー形式,
        &基礎.セットレイアウト,
        要求.描画シーン.先頭の描画対象().最詳細段の頂点一覧(),
        要求.スキン,
        要求.布,
        要求.シェーダー,
    )?;
    // 台帳は生のパイプラインとパイプラインレイアウトを持つため、失敗しうる生成の最後へ置く。
    // これより後に`?`で抜ける経路があると、その失敗で台帳が未破棄のまま落ちる。
    let パイプライン台帳 = vulkan::pipeline_ledger::材質描画族パイプライン台帳::生成する(
        device,
        &基礎.セットレイアウト,
        シーンカラー形式,
        要求.シェーダー,
        要求.フレーム構成.深度プリパス方式(),
    )?;

    Ok(bundle::束ねる(bundle::段別資源 {
        基礎,
        フレーム進行,
        描画段階,
        パイプライン台帳,
        粒子,
        gpu計測,
        ui一式,
        ポスト処理,
        スキニング,
        布,
    }))
}
