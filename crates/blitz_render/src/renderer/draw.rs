//! 1フレーム描画の公開エントリ。通常描画と読み戻し付き描画の2系を提供し、
//! 実行本体は`draw_execute`に委ねる。

use super::レンダラー;
use crate::draw_result::描画結果;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::readback_result::読み戻し結果;

impl レンダラー {
    /// 1フレーム分の描画を行い、可能ならスワップチェーンへ提示する。
    pub fn 一フレーム描画する(&mut self, 入力: フレーム描画入力) -> Result<描画結果, レンダラーエラー> {
        self.フレームを実行する(入力, false)
    }

    /// 1フレーム描画し、提示後にホスト可視バッファへ読み戻す。
    /// GPU同期(フェンス待機)を伴うためスモーク用途と文書化する（判断9）。
    pub fn 一フレーム描画して読み戻す(&mut self, 入力: フレーム描画入力) -> Result<読み戻し結果, レンダラーエラー> {
        match self.フレームを実行する(入力, true)? {
            描画結果::見送った(理由) => Ok(読み戻し結果::見送った(理由)),
            描画結果::提示した => Ok(読み戻し結果::読み戻した(self.読み戻しバッファから画像を作る()?)),
        }
    }
}
