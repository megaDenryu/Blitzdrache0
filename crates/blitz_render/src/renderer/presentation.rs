//! 提示側の資源と、その資源が要求寸法に追従しているかどうかの状態を1つに閉じる型。
//! 状態は資源そのものの性質であるため、資源と状態を別のフィールドに分けて持つと
//! 「ゼロ寸法なのに描画できる」「作り直したのに陳腐化のまま」という食い違いを作れる。
//! 資源への参照を外へ貸さず、ハンドルの読み出しを`描画許可`だけに通すため、状態の判別を経ない描画は書けない。
//! 状態と遷移は`state`、通行証は`permit`、生成と作り直しと破棄は`lifecycle`にある。

mod lifecycle;
mod permit;
mod state;

use ash::vk;

use super::present_resources::提示資源;
use crate::extent::ウィンドウ寸法;

pub(super) use permit::{取得済み提示, 描画許可};
pub(super) use state::提示状態;

pub(super) struct 提示 {
    資源: 提示資源,
    状態: 提示状態,
}

impl 提示 {
    /// フレーム開始時の分岐に使う現在の状態。
    pub(super) fn 状態(&self) -> 提示状態 {
        self.状態
    }

    /// 描画可能と観測できたときだけ通行証を返す。返らないあいだ提示資源のハンドルは読めない。
    pub(super) fn 描画許可(&self) -> Option<描画許可<'_>> {
        match self.状態 {
            提示状態::最小化中 | 提示状態::陳腐化 { .. } => None,
            提示状態::描画可能 { .. } => Some(描画許可::束ねる(&self.資源)),
        }
    }

    /// ウィンドウ寸法の通知を状態へ反映する。
    pub(super) fn 寸法変更を受ける(&mut self, 寸法: ウィンドウ寸法) {
        self.状態 = self.状態.寸法変更を受ける(寸法);
    }

    /// 取得または提示が報告した陳腐化をその場で反映する。
    ///
    /// 注意: 反映をフレームの結末までまとめて遅らせてはならない。送信が`Err`で戻る経路で
    /// 取得時に観測した陳腐化が失われ、陳腐化したスワップチェーンで次フレームを描くことになる。
    pub(super) fn 陳腐化した(&mut self) {
        self.状態 = self.状態.陳腐化した();
    }

    /// スワップチェーンが実際に決めた寸法。深度画像とポスト処理の中間画像はこの寸法に従う。
    pub(super) fn 寸法(&self) -> vk::Extent2D {
        self.資源.寸法()
    }

    /// スワップチェーン画像の色形式。シーンの描画先形式とパイプラインの色アタッチメント形式を決める。
    pub(super) fn 画像形式(&self) -> vk::Format {
        self.資源.画像形式()
    }

    /// 提示済み画像をホスト可視バッファへ転送する使い方をスワップチェーンが許すか。
    pub(super) fn 読み戻し対応(&self) -> bool {
        self.資源.読み戻し対応()
    }
}
