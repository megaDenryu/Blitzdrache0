//! フレームスロットに連動する資源と、そのスロットの巡回状態の束、およびそのコマンドバッファへ積み始める操作サービス。
//! コマンドバッファ・描画完了フェンス・取得セマフォの3つはすべて同じスロット番号で参照され、スロットが進むと参照先が揃って切り替わる。
//! 3つを別々に参照する手段を外へ出すと別スロットの資源が混ざるため、取り出しは`現在のスロット資源`の1つに限り、スロット番号を書き換える手段も外へ出さない。
//! 生成は`create`、スロットを進めるかどうかの規則は`slot_cycle`にある。

mod create;
mod slot_cycle;

use ash::vk;

use crate::error::レンダラーエラー;
use crate::vulkan;
use crate::vulkan::allocator::フレーム記録のコマンド一式;
use crate::vulkan::frame::{フレームのGPU命令を積むコマンドバッファ, フレームの記録の実行環境};
use crate::vulkan::sync::フレームスロット添字;
use crate::vulkan::tracked_device::GPUデバイス;
use slot_cycle::フレームスロット巡回;

pub(super) use slot_cycle::フレーム結末;

pub(super) struct フレーム進行 {
    コマンド一式: フレーム記録のコマンド一式,
    /// このコマンド一式のバッファへ1フレームぶんの積み込みを始める操作サービス。バッファの持ち主と積み始めの口を同じ型に置き、記録を頼む側に論理デバイスとキューを運ばせない。
    記録の実行環境: フレームの記録の実行環境,
    フレーム同期: vulkan::sync::フレーム同期,
    巡回: フレームスロット巡回,
    /// 提示へ到達しなかったフレームの累計。提示停止に起因する異常(破棄待ちの滞留・フレームループの空転)を実行中に観測する計器である。
    見送り累計: u64,
}

/// 現在のスロットで参照した資源一式。3つを同時に取り出すため、別スロットの資源が混ざった組み合わせを作れない。
pub(super) struct フレームスロット資源 {
    pub(super) スロット: フレームスロット添字,
    pub(super) フェンス: vk::Fence,
    pub(super) 取得セマフォ: vk::Semaphore,
    pub(super) command_buffer: vk::CommandBuffer,
}

impl フレーム進行 {
    pub(super) fn 現在のスロット資源(&self) -> フレームスロット資源 {
        let スロット = self.巡回.現在のスロット();
        フレームスロット資源 {
            スロット,
            フェンス: self.フレーム同期.フェンス(スロット),
            取得セマフォ: self.フレーム同期.取得セマフォ(スロット),
            command_buffer: self.コマンド一式.スロットのコマンドバッファ(スロット.配列添字()),
        }
    }

    /// そのフレームのスロットのコマンドバッファへ、1フレームぶんの積み込みを始める。
    /// 返る値は`記録を閉じて送信し提示する`で必ず閉じる。閉じないまま捨てると`破棄する`が止める。
    pub(super) fn フレームのgpu命令を積み始める(
        &self,
        スロット資源: &フレームスロット資源,
        クエリプール: Option<vk::QueryPool>,
    ) -> Result<フレームのGPU命令を積むコマンドバッファ<'_>, レンダラーエラー> {
        self.記録の実行環境
            .フレームのgpu命令を積み始める(スロット資源.command_buffer, クエリプール)
    }

    /// 直近に描き終えたスロット。巡回は提示したフレームの後に次のスロットへ進むため、1つ前が最後に書いたスロットである。
    /// 読むのは検収の読み戻しだけであり、毎フレームの描画経路は`現在のスロット資源`しか通らない。
    pub(super) fn 直近に描いたスロット(&self) -> フレームスロット添字 {
        self.巡回.現在のスロット().前のスロット()
    }

    /// 提示まで到達したフレームだけがスロットを進める。見送りと失敗では据え置き、次フレームが同じスロットの資源を使う。
    pub(super) fn 結末を反映する(&mut self, 結末: フレーム結末) {
        if let フレーム結末::見送った = 結末 {
            self.見送り累計 = self.見送り累計.saturating_add(1);
        }
        self.巡回.結末を反映する(結末);
    }

    pub(super) fn 見送りフレーム数(&self) -> u64 {
        self.見送り累計
    }

    /// 前提: レンダラー全体の破棄順は renderer/destroy.rs が持ち、この束はその1段として呼ばれる(GPU待機済み)。
    pub(super) fn 破棄する(&self, device: &GPUデバイス) {
        self.記録の実行環境.未送信が1本も残っていないことを確かめる();
        self.フレーム同期.破棄する(device);
        self.コマンド一式.破棄する(device);
    }
}
