use super::{CPU区間時間, CPU区間計測};

#[test]
fn ウォームアップ後だけ記録する() {
    let 標本 = CPU区間時間 {
        フェンス待機ms: 1.0,
        フレームデータ準備ms: 2.0,
        画像取得ms: 3.0,
        記録送信提示ms: 4.0,
        作業領域更新ms: 5.0,
        描画記録送信提示ms: 6.0,
    };
    let mut 計測 = CPU区間計測::生成する(2, 1);
    計測.記録する(標本);
    計測.記録する(標本);
    計測.記録する(標本);
    assert_eq!(計測.時間一覧().len(), 1);
    assert_eq!(計測.時間一覧()[0].画像取得ms, 3.0);
    assert_eq!(計測.時間一覧()[0].作業領域更新ms, 5.0);
}
