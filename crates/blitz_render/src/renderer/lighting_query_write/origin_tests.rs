//! 大域の平行移動を加えても照明のレコードが同じバイト列になることの検査。
//! 方向光は平行移動で値が変わらず、局所光はカメラ相対化で差が打ち消されるという2つの性質を、
//! 読み戻し画像でなくレコードのバイト列で直接見る
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段5の検収ゲート(iv))。

#![allow(clippy::unwrap_used)]

use blitz_math::{クリップ, ビュー, メートル, ラジアン, ワールド, 位置, 変換, 大域メートル, 大域ワールド位置};

use super::組み立てる;
use crate::frame_lighting::フレーム照明入力;
use crate::lighting_input::{
    ライティング入力, 光強度, 光色, 影の落ち方, 影入力, 影正射影範囲, 方向光入力, 点光源入力, 環境光係数
};
use crate::view_input::描画視点;
use crate::vulkan::lighting_query::{directional_bytes, local_bytes};

/// 大域のkm級の平行移動。原点不変の検収入口が使う量と同じ桁である。
const 平行移動メートル: f64 = 12_000.0;

fn 大域位置(x: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(x), 大域メートル::生成する(2.0), 大域メートル::生成する(-3.0))
}

fn 視点を作る(ずらし: f64) -> 描画視点 {
    let 位置 = 位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(1.0), メートル::生成する(4.0));
    let 注視点 = 位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0));
    let ビュー: 変換<ワールド, ビュー> = 変換::注視(位置, 注視点);
    let 投影: 変換<ビュー, クリップ> = 変換::透視投影(ラジアン::度から(60.0), 1.0, メートル::生成する(0.1), メートル::生成する(500.0));
    let 原点 = 大域位置(ずらし);
    let 復元 =
        crate::local_visibility::射影の復元::生成する(メートル::生成する(0.1), メートル::生成する(500.0), ラジアン::度から(60.0), 1.0)
            .unwrap_or_else(|誤り| panic!("検査の射影の復元が作れない: {誤り}"));
    描画視点::生成する(ビュー.合成する(投影), 原点, 原点, 復元)
}

fn 照明を作る(ずらし: f64) -> フレーム照明入力 {
    let 色 = 光色::生成する(0.9, 0.8, 0.7).unwrap();
    let 強度 = 光強度::生成する(3.0).unwrap();
    let 方向光 = 方向光入力::生成する(0.3, -0.9, 0.2, 色, 強度).unwrap();
    let 点光源 = 点光源入力::生成する(大域位置(ずらし + 5.0), 色, 強度).unwrap();
    let 範囲 = 影正射影範囲::生成する(
        メートル::生成する(20.0),
        メートル::生成する(20.0),
        メートル::生成する(1.0),
        メートル::生成する(200.0),
    )
    .unwrap();
    let 影 = 影入力::生成する(大域位置(ずらし), メートル::生成する(60.0), 範囲).unwrap();
    let 入力 = ライティング入力::生成する(方向光, 点光源, 環境光係数::生成する(0.2).unwrap(), 影, 影の落ち方::落とす, true);
    フレーム照明入力::ライティング入力から写す(&入力)
}

fn レコードのバイト列(ずらし: f64) -> ([u8; directional_bytes::バイト長], [u8; local_bytes::バイト長]) {
    let 内容 = 組み立てる(&照明を作る(ずらし), None, &視点を作る(ずらし)).unwrap();
    (
        directional_bytes::バイト列にする(&内容.方向光一覧[0]),
        local_bytes::バイト列にする(&内容.局所光一覧[0]),
    )
}

#[test]
fn 大域の平行移動を加えても方向光と局所光のレコードがバイト一致する() {
    let (原点での方向光, 原点での局所光) = レコードのバイト列(0.0);
    let (移動後の方向光, 移動後の局所光) = レコードのバイト列(平行移動メートル);
    assert_eq!(原点での方向光, 移動後の方向光);
    assert_eq!(原点での局所光, 移動後の局所光);
}

#[test]
fn 局所光がカメラ相対で表され大域の値をそのまま持たない() {
    let 内容 = 組み立てる(&照明を作る(平行移動メートル), None, &視点を作る(平行移動メートル)).unwrap();
    assert!((内容.局所光一覧[0].カメラ相対位置[0] - 5.0).abs() < 1e-3);
}
