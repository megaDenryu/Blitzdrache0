//! 大域の平行移動を加えても照明のレコードが同じバイト列になることの検査。
//! 方向光は平行移動で値が変わらず、局所光はカメラ相対化で差が打ち消されるという2つの性質を、
//! 読み戻し画像でなくレコードのバイト列で直接見る
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段5の検収ゲート(iv))。

#![allow(clippy::unwrap_used)]

mod fixture;

use fixture::{クラスタ写像を作る, 平行移動メートル, 照明を作る, 視点を作る};

use super::{照明問い合わせの書き込み内容, 照明問い合わせの書き込み内容を組み立てる};
use crate::vulkan::lighting_query::{directional_bytes, local_bytes, 局所光レコード内容};

#[test]
fn 大域の平行移動を加えても方向光と局所光のレコードがバイト一致する() {
    let 原点 = 書き込み内容を作る(0.0);
    let 移動後 = 書き込み内容を作る(平行移動メートル);
    assert_eq!(方向光のバイト列(&原点), 方向光のバイト列(&移動後));
    assert_eq!(局所光のバイト列(&原点), 局所光のバイト列(&移動後));
}

#[test]
fn 局所光がカメラ相対で表され大域の値をそのまま持たない() {
    let 内容 = 書き込み内容を作る(平行移動メートル);
    assert!((先頭の局所光レコード(&内容).カメラ相対位置[0] - 5.0).abs() < 1e-3);
}

fn 書き込み内容を作る(ずらし: f64) -> 照明問い合わせの書き込み内容 {
    照明問い合わせの書き込み内容を組み立てる(&照明を作る(ずらし), None, &視点を作る(ずらし), クラスタ写像を作る()).unwrap()
}

/// 検査の入力は局所光を1件だけ宣言するため、先頭の1件がその光である。
fn 先頭の局所光レコード(内容: &照明問い合わせの書き込み内容) -> &局所光レコード内容 {
    let mut 並び = 内容.局所光一覧.局所光レコードを先頭から順に返す();
    並び.next().unwrap_or_else(|| panic!("検査の入力は局所光を1件持つ"))
}

fn 方向光のバイト列(内容: &照明問い合わせの書き込み内容) -> [u8; directional_bytes::バイト長] {
    directional_bytes::方向光レコード内容をバイト列にする(&内容.方向光一覧[0])
}

fn 局所光のバイト列(内容: &照明問い合わせの書き込み内容) -> [u8; local_bytes::バイト長] {
    local_bytes::局所光レコード内容をバイト列にする(先頭の局所光レコード(内容))
}
