//! 原点不変の検査が使う素材の組み立て。受け取るのは大域のずらし量、返すのは同じ世界を同じ量だけ動かした
//! 視点と照明とクラスタ写像である。
//!
//! 素材を判定と分けるのは、判定が見るのは2つの実行の差だけであり、素材の作り方を知る必要が無いためである。
//! ずらし量を全ての大域位置へ同じだけ足すことがこの素材の不変条件であり、ここが1箇所で守る。

use std::fmt::Debug;

use blitz_math::{
    クリップ, ビュー, メートル, ラジアン, ワールド, 位置, 変換, 大域メートル, 大域ワールド位置, 画素内ずらし
};

use crate::clustered_lighting::{
    クラスタの奥行き範囲, クラスタ写像, クラスタ格子の分割数, 影響半径, 視野の半角の正接
};
use crate::extent::ウィンドウ寸法;
use crate::frame_lighting::フレーム照明入力;
use crate::lighting_input::点光源の可視性;
use crate::lighting_input::{
    ライティング入力, 光強度, 光色, 局所光源列, 影の落ち方, 影入力, 影正射影範囲, 方向光入力, 点光源入力, 環境光係数
};
use crate::view_input::{ビュー射影の組, 描画視点};

/// 大域のkm級の平行移動。原点不変の検収入口が使う量と同じ桁である。
pub(super) const 平行移動メートル: f64 = 12_000.0;

/// 検査用の固定値から作る値は必ず成立するため、失敗は検査自身のバグである。
fn 検査用の固定値から作った値を取り出す<値, 誤り: Debug>(結果: Result<値, 誤り>) -> 値 {
    match 結果 {
        Ok(値) => 値,
        Err(理由) => panic!("検査用の固定値が値オブジェクトの不変条件を満たしていない: {理由:?}"),
    }
}

pub(super) fn 視点を作る(ずらし: f64) -> 描画視点 {
    let 位置 = 位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(1.0), メートル::生成する(4.0));
    let 注視点 = 位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0));
    let ビュー: 変換<ワールド, ビュー> = 変換::注視(位置, 注視点);
    let 投影: 変換<ビュー, クリップ> =
        変換::逆向き深度の透視投影(ラジアン::度から(60.0), 1.0, メートル::生成する(0.1), メートル::生成する(500.0));
    let 原点 = 大域位置(ずらし);
    let 復元 = 検査用の固定値から作った値を取り出す(crate::local_visibility::射影の復元::生成する(
        メートル::生成する(0.1),
        メートル::生成する(500.0),
        ラジアン::度から(60.0),
        1.0,
        画素内ずらし::ずらさない(),
    ));
    let ビュー射影 = ビュー.合成する(投影);
    描画視点::生成する(ビュー射影の組::生成する(ビュー射影, ビュー射影, ビュー射影), ビュー, 原点, 原点, 復元)
}

pub(super) fn 照明を作る(ずらし: f64) -> フレーム照明入力 {
    let 色 = 検査用の固定値から作った値を取り出す(光色::生成する(0.9, 0.8, 0.7));
    let 強度 = 検査用の固定値から作った値を取り出す(光強度::生成する(3.0));
    let 方向光 = 検査用の固定値から作った値を取り出す(方向光入力::生成する(0.3, -0.9, 0.2, 色, 強度));
    let 局所光源列 = 局所光源列を作る(ずらし, 色, 強度);
    let 影 = 影入力を作る(ずらし);
    let 環境光 = 検査用の固定値から作った値を取り出す(環境光係数::生成する(0.2));
    let 入力 = ライティング入力::生成する(方向光, 局所光源列, 環境光, 影, 影の落ち方::落とす, true);
    フレーム照明入力::ライティング入力から写す(&入力)
}

/// 写像は大域のずらし量に依らない。判定はレコードの差だけを見るため、両方の実行へ同じ値を渡す。
pub(super) fn クラスタ写像を作る() -> クラスタ写像 {
    let 奥行き範囲 = クラスタの奥行き範囲::生成する(メートル::生成する(0.1), メートル::生成する(500.0));
    検査用の固定値から作った値を取り出す(クラスタ写像::生成する(
        クラスタ格子の分割数::仮置きの分割数を返す(),
        ウィンドウ寸法::生成する(800, 600),
        検査用の固定値から作った値を取り出す(奥行き範囲),
        検査用の固定値から作った値を取り出す(視野の半角の正接::生成する(1.0, 0.75)),
    ))
}

fn 局所光源列を作る(ずらし: f64, 色: 光色, 強度: 光強度) -> 局所光源列 {
    let 半径 = 検査用の固定値から作った値を取り出す(影響半径::生成する(メートル::生成する(30.0)));
    let 点光源 = 検査用の固定値から作った値を取り出す(点光源入力::生成する(
        大域位置(ずらし + 5.0),
        色,
        強度,
        半径,
        点光源の可視性::影なし,
    ));
    検査用の固定値から作った値を取り出す(局所光源列::生成する(&[点光源]))
}

fn 影入力を作る(ずらし: f64) -> 影入力 {
    let 範囲 = 影正射影範囲::生成する(
        メートル::生成する(20.0),
        メートル::生成する(20.0),
        メートル::生成する(1.0),
        メートル::生成する(200.0),
    );
    let 範囲 = 検査用の固定値から作った値を取り出す(範囲);
    検査用の固定値から作った値を取り出す(影入力::生成する(大域位置(ずらし), メートル::生成する(60.0), 範囲))
}

fn 大域位置(x: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(x), 大域メートル::生成する(2.0), 大域メートル::生成する(-3.0))
}
