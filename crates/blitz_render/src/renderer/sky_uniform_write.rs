//! 空パス定数の書き込みと、空パスが束縛する資源の組み立て。書くか書かないかの判断は
//! `vulkan/uniform/sky_write_order`が持ち、ここは書く指示を受けたときだけ逆行列を求めてGPUへ反映する。
//!
//! 不変条件: 空パス資源の有無とフレーム描画入力の空の有無は常に一致する。不一致は型付きエラーにする。

use blitz_math::{クリップ, ワールド, 変換};

use super::レンダラー;
use crate::error::{レンダラーエラー, 空エラー};
use crate::frame_input::フレーム描画入力;
use crate::vulkan::frame::空描画入力;
use crate::vulkan::sync::フレームスロット添字;
use crate::vulkan::uniform::sky_write_order::{決める, 空パス定数の書込指示};
use crate::vulkan::uniform::空パス定数内容;

impl レンダラー {
    pub(super) fn 空パスの定数を書き込む(
        &self,
        フレーム添字: フレームスロット添字,
        入力: &フレーム描画入力<'_>,
        ビュー射影: 変換<ワールド, クリップ>,
    ) -> Result<(), レンダラーエラー> {
        match 決める(self.描画段階資源.空を描くか(), 入力.空.as_ref())? {
            空パス定数の書込指示::書き込む(空入力) => {
                let 逆行列 = 逆ビュー射影を求める(ビュー射影)?;
                let 内容 = 空パス定数内容::組み立てる(空入力, 逆行列);
                self.シェーダー定数.空パスの定数を書き込む(self.環境.device(), フレーム添字, &内容)
            }
            空パス定数の書込指示::書き込まない => Ok(()),
        }
    }

    /// 空パスが束縛する資源を集める。係数は空パス定数に載るため、ここではパイプラインと束縛先だけを運ぶ。
    /// 束縛先のディスクリプタセットが1つも無いフレームは、空を無言で描かずに型付きエラーにする。
    pub(super) fn 空描画入力を組み立てる(
        &self,
        フレーム添字: フレームスロット添字,
    ) -> Result<Option<空描画入力>, レンダラーエラー> {
        if !self.描画段階資源.空を描くか() {
            return Ok(None);
        }
        let Some(セット) = self.シーン描画資源.先頭描画対象のディスクリプタセット(フレーム添字) else {
            return Err(空エラー::入力不一致("空を描く束縛先の描画対象が1つも無い".to_string()).into());
        };
        Ok(self.描画段階資源.空描画入力を作る(セット, フレーム添字))
    }
}

/// GPU境界(生型境界): クリップ座標からカメラ相対ワールドへ戻す行列を列優先配列で返す。
/// ビューと透視投影の合成は常に正則であるため逆は存在するが、外部から渡る行列が退化していれば
/// 成分が非有限になる。その場合は無言で不定の空を描かず型付きエラーにする。
fn 逆ビュー射影を求める(ビュー射影: 変換<ワールド, クリップ>) -> Result<[[f32; 4]; 4], レンダラーエラー> {
    let 配列 = ビュー射影.逆変換する().gpu境界用列優先配列();
    if 配列.iter().flatten().any(|値| !値.is_finite()) {
        return Err(空エラー::逆行列が非有限.into());
    }
    Ok(配列)
}
