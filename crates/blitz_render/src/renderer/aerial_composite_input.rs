//! 空中遠近合成パスが束縛する資源を集める工程。担当するのは「そのフレームの大気入力から最遠距離を取り、
//! 走査順で最初の描画対象のディスクリプタセットと合わせて合成の入力を作る」ことである。
//!
//! 最遠距離を空パス定数から取らずここで大気入力から取るのは、焼く側の即時定数と同じ1つの値
//! (空中遠近観測条件)を出どころにするためである。写しを増やすと焼いた刻みと参照する刻みが食い違いうる。
//!
//! 合成を持たない構成(起動指定`--no-aerial-composite`で合成を切った構成)では`None`を返す。大気入力が無い構成でも`None`である。
//! 空段階との有無の食い違いは`空描画入力を組み立てる`が先に型付きエラーで落とすため、ここでは判定を重ねない。

use super::レンダラー;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::vulkan::frame::空中遠近合成描画入力;
use crate::vulkan::sync::フレームスロット添字;

impl レンダラー {
    pub(super) fn 空中遠近合成入力を組み立てる(
        &self,
        フレーム添字: フレームスロット添字,
        入力: &フレーム描画入力<'_>,
    ) -> Result<Option<空中遠近合成描画入力>, レンダラーエラー> {
        let Some(大気) = 入力.大気.as_ref() else {
            return Ok(None);
        };
        if !self.描画段階資源.空中遠近を参照するか() {
            return Ok(None);
        }
        let セット = self.共有ディスクリプタ.ビューとパス(フレーム添字);
        let 最遠距離 = 大気.空中遠近条件().最遠距離().値();
        Ok(self.描画段階資源.空中遠近合成描画入力を作る(セット, フレーム添字, 最遠距離))
    }
}
