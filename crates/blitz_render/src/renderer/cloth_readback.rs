//! 布の粒子の位置とラグランジュ乗数をホストへ写す口。触れるフィールドは`布`・`環境`・`転送環境`に限る。
//! 検収の突き合わせがプロセスの終わりに1回だけ呼ぶ。毎フレームは呼ばない(判断10・Issue #36「描画経路」)。

use super::レンダラー;
use crate::cloth_material::布の読み戻し;
use crate::error::レンダラーエラー;

impl レンダラー {
    /// GPUの全作業の完了を待ってから、布の粒子の位置とラグランジュ乗数をホストへ写す。布を持たないレンダラーでは`None`である。
    pub fn 布の粒子と乗数を読み戻す(&self) -> Result<Option<布の読み戻し>, レンダラーエラー> {
        let Some(布) = &self.布 else {
            return Ok(None);
        };
        self.環境.gpuの全作業完了を待つ()?;
        let 確保係 = self.環境.資源の確保係を貸す();
        布.粒子と乗数を読み戻す(&確保係, &self.転送環境).map(Some)
    }
}
