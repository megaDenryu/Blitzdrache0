//! ビュー定数の内容を組み立てる工程。受け取るのは描画視点・ビュー射影の行列一式・組み立て済みの多段一式、
//! 返すのはGPUへ書ける定数内容である。レンダラーの状態には触れない。
//!
//! カメラ位置は焼いた値でなく、毎フレームここでカメラ大域原点を引いて組み立てる。
//! 照明の値はこの定数に無い。直接光は照明問い合わせ資源へ書く(`lighting_query_write`)。

use blitz_math::大域ワールド位置;

use crate::cascade::多段一式;
use crate::error::レンダラーエラー;
use crate::view_input::描画視点;
use crate::vulkan::uniform::ビュー定数内容;

/// ビュー定数へ載る2本の行列を、フレーム型から生値へ戻した形。2本を1つにするのは、どちらも同じ
/// `[[f32; 4]; 4]`であり、引数として並べると取り違えが型検査に掛からないためである。
#[derive(Debug, Clone, Copy)]
pub(super) struct ビュー射影の行列一式 {
    ずらし付き: [[f32; 4]; 4],
    前フレーム: [[f32; 4]; 4],
}

impl ビュー射影の行列一式 {
    /// GPU境界(生型境界): 視点が持つフレーム型の変換を列優先配列へ戻す。
    pub(super) fn 視点から写す(視点: &描画視点) -> Self {
        let 組 = 視点.ビュー射影の組();
        Self {
            ずらし付き: 組.ずらし付き().gpu境界用列優先配列(),
            前フレーム: 組.前フレーム().gpu境界用列優先配列(),
        }
    }
}

pub(super) fn 組み立てる(
    視点: &描画視点,
    行列一式: &ビュー射影の行列一式,
    多段: &多段一式,
) -> Result<ビュー定数内容, レンダラーエラー> {
    let 原点 = 視点.カメラ大域原点();
    Ok(ビュー定数内容 {
        ビュー射影行列: 行列一式.ずらし付き,
        カメラ相対位置: 大域位置をgpu境界配列にする(視点.カメラ大域位置(), 原点)?,
        カメラ前方: 多段.カメラ前方(),
        前フレームのビュー射影行列: 行列一式.前フレーム,
    })
}

/// GPU境界(生型境界): カメラ大域原点を引いてからf32の生値へ戻す。f64での減算が精度を守る唯一の境界である
/// (数学DDD。参照: CLAUDE.md「型安全性」)。
fn 大域位置をgpu境界配列にする(
    位置: 大域ワールド位置, カメラ大域原点: 大域ワールド位置
) -> Result<[f32; 3], レンダラーエラー> {
    let 相対 = 位置.カメラ相対へ変換する(カメラ大域原点)?;
    Ok([相対.x().値(), 相対.y().値(), 相対.z().値()])
}
