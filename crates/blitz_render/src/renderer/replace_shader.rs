//! ホットリロード時のパイプライン差し替え。
//! 参照: `_doc/開発スレッド/開発スレッド_2026-07-20_M0実装.md`「判断7」「判断10」。

use super::レンダラー;
use crate::error::レンダラーエラー;
use crate::shader_set::シェーダー一式;

impl レンダラー {
    /// 新しいシェーダー一式で全シーンキーの新しい表を先に構築し、GPUの全作業完了を待ってから表を交換して旧いパイプラインを破棄する。
    /// 構築に失敗した場合は台帳を1つも変えずにエラーを返す(呼び出し元のblitz_appはこれを「コンパイル失敗、旧パイプライン継続」として扱う)。
    /// シャドウの表を触らないのは、差し替えるのがシーンのシェーダーだけだからである。
    /// パイプラインレイアウトは族で共有して作り直さないため、交換の前後でディスクリプタセットの束縛の互換性は変わらない。
    pub fn シェーダーを差し替える(&mut self, シェーダー: シェーダー一式) -> Result<(), レンダラーエラー> {
        let device = self.環境.device();
        let 新表 = self.パイプライン台帳.シーンの新表を構築する(device, &シェーダー)?;
        self.環境.gpuの全作業完了を待つ()?;
        self.パイプライン台帳.シーンの表を交換する(device, 新表);
        Ok(())
    }
}
