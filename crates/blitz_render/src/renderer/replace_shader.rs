//! ホットリロード時のパイプライン差し替え。
//! 参照: `_doc/開発スレッド/開発スレッド_2026-07-20_M0実装.md`「判断7」「判断10」。

use super::レンダラー;
use crate::error::レンダラーエラー;
use crate::indirect_lighting::契約別の描画シェーダー;

impl レンダラー {
    /// 新しいシェーダーの束で全シーンキーの新しい表を先に構築し、GPUの全作業完了を待ってから表を交換して旧いパイプラインを破棄する。
    /// 構築に失敗しても待機に失敗しても台帳を1つも変えずにエラーを返す(呼び出し元のblitz_appはこれを「コンパイル失敗、旧パイプライン継続」として扱う)。
    /// 待機を台帳へ関数として渡すのは、待機が失敗した局面で新しく作ったパイプラインを捨てる後始末を台帳の側に閉じるためである。
    /// シャドウの表を触らないのは、差し替えるのがシーンのシェーダーだけだからである。
    /// パイプラインレイアウトは族で共有して作り直さないため、交換の前後でディスクリプタセットの束縛の互換性は変わらない。
    /// 束を値で受け取って交換の後に落とすのは、台帳が保つのが構築済みのパイプライン表であり、SPIR-Vのバイト列を
    /// 持ち続ける理由が1つも無いためである。
    pub fn シェーダーを差し替える(&mut self, シェーダー: 契約別の描画シェーダー) -> Result<(), レンダラーエラー> {
        let 環境 = &self.環境;
        let 確保係 = 環境.資源の確保係を貸す();
        let 結果 = self
            .パイプライン台帳
            .シーンを差し替える(&確保係, &シェーダー, || 環境.gpuの全作業完了を待つ());
        // 差し替えが成った時だけ履歴を捨てる。判断cの無効化条件の1つであり、新しいシェーダーが描く色を
        // 古いシェーダーが描いた履歴と混ぜると、切り替えの直後だけ前の見た目が残る。
        if 結果.is_ok() {
            self.時間再構成.履歴を無効にする();
        }
        結果
    }
}
