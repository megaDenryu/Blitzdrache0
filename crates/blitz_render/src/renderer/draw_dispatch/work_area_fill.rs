//! そのフレームの描画発行の作業領域を積む工程。受け取るのはレンダラーとフレームごとに変わる材料、返すのは無しである。
//! 呼ばれるのは描画コマンドの記録より前の1回だけであり、CPU区間の計測の刻みもここに閉じる。
//!
//! 独立した工程として切るのは、積むのに要る値がレンダラーの複数のフィールド(スキニング・パイプライン台帳・材質資源表)に
//! またがり、呼び出し元が組み立てると描画の呼び出しの中に資源の取り出しが混ざるためである。
//! 同じ理由で、積む前に済ませておく資源表世代の確定と束縛もここが持つ。

use blitz_math::大域ワールド位置;

use super::super::cpu_timing::CPU区間時計;
use super::super::scene_draw_resources::作業領域更新入力;
use super::super::レンダラー;
use crate::error::レンダラーエラー;
use crate::frame_input::プリミティブ発行受け皿;
use crate::terrain_detail::地形詳細段選択;
use crate::visible_instance_selection::可視個体選択一覧;
use crate::vulkan::material_table::{材質資源の作業環境, 資源表世代の束縛};
use crate::vulkan::skinning::スキニング一式;
use crate::vulkan::sync::フレームスロット添字;

/// フレームごとに変わる、レンダラーのフィールドから取れない材料。
pub(super) struct 充填の材料<'a> {
    pub(super) フレーム添字: フレームスロット添字,
    pub(super) 資源表世代の束縛: 資源表世代の束縛,
    pub(super) カメラ大域原点: 大域ワールド位置,
    pub(super) 地形詳細段選択一覧: &'a [地形詳細段選択],
    pub(super) 可視個体選択一覧: 可視個体選択一覧<'a>,
    pub(super) プリミティブ発行: &'a プリミティブ発行受け皿,
}

pub(super) fn 積む(
    レンダラー: &mut レンダラー, 材料: 充填の材料<'_>, mut 時計: Option<&mut CPU区間時計>
) -> Result<(), レンダラーエラー> {
    // スキン付きシーンでは先頭対象の頂点入力をスキン済みバッファへ差し替える(判断44)。
    let 入力 = 作業領域更新入力 {
        device: レンダラー.環境.device(),
        フレーム添字: 材料.フレーム添字,
        スキン済み頂点バッファ: レンダラー.スキニング.as_ref().map(スキニング一式::出力バッファ),
        パイプライン台帳: &レンダラー.パイプライン台帳,
        カメラ大域原点: 材料.カメラ大域原点,
        地形詳細段選択一覧: 材料.地形詳細段選択一覧,
        可視個体選択一覧: 材料.可視個体選択一覧,
        プリミティブ発行: 材料.プリミティブ発行,
        材質資源表: &レンダラー.材質資源表,
        資源表世代の束縛: 材料.資源表世代の束縛,
    };
    if let Some(時計) = 時計.as_deref_mut() {
        時計.作業領域更新を開始する();
    }
    let 結果 = レンダラー.シーン描画資源.作業領域を更新する(&入力);
    if let Some(時計) = 時計 {
        時計.作業領域更新を終了する();
    }
    結果
}

impl レンダラー {
    /// 束の出し入れで溜まった材質を1つの資源表世代へ反映し、そのフレームが読む束縛先を借りる。
    /// 1フレームに1回だけ作り直すため、同じフレームで束が何個増減しても生まれる世代は1つである。
    /// 保持の記録はここで行わない。送信へ到達しなかったフレームが世代を保持したままにならないよう、
    /// コマンドを送り終えた後に`フレームの保持を記録する`で確定する。
    pub(super) fn 資源表世代を最新にして束縛を借りる(&mut self) -> Result<資源表世代の束縛, レンダラーエラー> {
        let メモリプロパティ = self.環境.メモリプロパティを取得する();
        let 作業環境 = 材質資源の作業環境 {
            device: self.環境.device(),
            問い合わせ: self.環境.物理デバイス問い合わせ(),
            メモリプロパティ: &メモリプロパティ,
            転送環境: &self.転送環境,
            セットレイアウト: &self.セットレイアウト,
        };
        self.材質資源表.世代を最新にする(作業環境)?;
        Ok(self.材質資源表.公開中の束縛を借りる())
    }
}
