//! そのフレームの描画対象入力を組み立てる工程。受け取るのはフレームスロット添字と資源表世代の束縛と描画視点、返すのは描画対象入力である。
//!
//! 組み立てを1箇所へ置くのは、この値がレンダラー直下の5つの持ち物(共有ディスクリプタ・照明問い合わせ資源・記録の計器・
//! シーン描画資源・描画段階資源)とパイプライン台帳から同時に決まるためである。呼び出し側で並べると、どれか1つだけ別のフレームの値を渡す
//! 組み合わせが書き間違いだけで成立する。

use crate::renderer::レンダラー;
use crate::view_input::描画視点;
use crate::vulkan::frame::描画対象入力;
use crate::vulkan::material_table::資源表世代の束縛;
use crate::vulkan::sync::フレームスロット添字;

impl レンダラー {
    pub(super) fn 描画対象入力を組み立てる(
        &self,
        フレーム添字: フレームスロット添字,
        資源表世代の束縛: 資源表世代の束縛,
        視点: &描画視点,
    ) -> 描画対象入力<'_> {
        let 共有 = self.共有ディスクリプタ.束縛を作る(
            フレーム添字,
            資源表世代の束縛.材質のセット,
            self.照明問い合わせ資源.セット(フレーム添字),
            &self.記録の計器,
        );
        let クラスタ選別 = self.描画段階資源.クラスタ選別の描画入力を作る(フレーム添字, 視点.カメラ相対ビュー変換());
        self.シーン描画資源
            .描画対象入力を作る(共有, self.パイプライン台帳.深度プリパス方式(), クラスタ選別)
    }
}
