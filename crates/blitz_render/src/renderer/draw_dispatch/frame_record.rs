//! セッション型を通した1フレームの記録・送信・提示。担当する工程は、スロットのコマンドバッファへ積み始め、
//! そのフレームのグラフを積み、記録を閉じて送信し提示するまでの3手であり、受け取るのは記録の材料とスロットの資源、
//! 返すのは送信後の結末と記録の実績である。
//!
//! 積む側がデバイスもキューもコマンドバッファも引数で運ばないのは、その3つを`フレームの記録の実行環境`が保持し、
//! 積み始めが返すセッション型だけが積み先を知るためである。

use ash::vk;

use crate::error::レンダラーエラー;
use crate::renderer::frame_progress::フレームスロット資源;
use crate::renderer::presentation::取得済み提示;
use crate::renderer::レンダラー;
use crate::vulkan::frame::{フレームの記録の材料, 記録の実績, 送信後の結末};

impl レンダラー {
    pub(super) fn 記録して送信し提示する(
        &self,
        スロット資源: &フレームスロット資源,
        取得済み: &取得済み提示,
        提示id: Option<u64>,
        クエリプール: Option<vk::QueryPool>,
        材料: フレームの記録の材料<'_>,
    ) -> Result<(送信後の結末, 記録の実績), レンダラーエラー> {
        let 読み戻しの待機 = 材料.描画方式.読み戻しの待機();
        let 積み込み = self.フレーム進行.フレームのgpu命令を積み始める(スロット資源, クエリプール)?;
        let 実績 = 積み込み.フレームのgpu命令を積む(材料);
        let 同期 = self.同期入力を組み立てる(スロット資源, 取得済み);
        let 結末 = 積み込み.記録を閉じて送信し提示する(self.提示先を組み立てる(取得済み, 提示id), &同期, 読み戻しの待機)?;
        Ok((結末, 実績))
    }
}
