//! そのフレームの描画後処理を「通常の提示前遷移だけ」か「読み戻し用のコピーを挟む」かで決める。
//! 触れるのはフレーム構成と読み戻しバッファの2つだけであり、描画資源にもフレームスロットにも触れない。
//! 読み戻しを要求されたのに、その対象を作る段階が構成に無い場合を型付きエラーにするのがこの操作の役目である。

use super::super::レンダラー;
use crate::error::{フレーム入力不一致エラー, レンダラーエラー};
use crate::frame_composition::フレーム段階;
use crate::vulkan::frame::描画方式;
use crate::vulkan::readback::読み戻し対象;

impl レンダラー {
    pub(super) fn 描画方式を決める(&self, 読み戻し要求: Option<読み戻し対象>) -> Result<描画方式, レンダラーエラー> {
        let Some(対象) = 読み戻し要求 else {
            return Ok(描画方式::通常);
        };
        if !self.フレーム構成.含む(フレーム段階::読み戻し) {
            return Err(フレーム入力不一致エラー::読み戻し段階なし.into());
        }
        // ポスト処理が無い構成ではシーンが直接スワップチェーンへ描くため、圧縮前のHDR中間画像そのものが存在しない。
        if 対象 == 読み戻し対象::圧縮前のHDR && !self.フレーム構成.含む(フレーム段階::光のにじみと明るさの圧縮)
        {
            return Err(フレーム入力不一致エラー::圧縮前のHDRの読み戻しにポスト処理が要る.into());
        }
        let バッファ = self
            .読み戻しバッファ
            .as_ref()
            .unwrap_or_else(|| panic!("読み戻し要求時に読み戻しバッファが未確保だった"));
        Ok(描画方式::読み戻し {
            バッファ: バッファ.handle(),
            対象,
        })
    }
}
