//! そのフレームの描画後処理を「通常の提示前遷移だけ」か「読み戻し用のコピーを挟む」かで決める。
//! 触れるのはフレーム構成と読み戻しバッファの2つだけであり、描画資源にもフレームスロットにも触れない。
//! 読み戻しを要求されたのに段階が構成に無い場合を型付きエラーにするのがこの操作の役目である。

use super::super::レンダラー;
use crate::error::レンダラーエラー;
use crate::frame_composition::フレーム段階;
use crate::vulkan::frame::描画方式;

impl レンダラー {
    pub(super) fn 描画方式を決める(&self, 読み戻し要求: bool) -> Result<描画方式, レンダラーエラー> {
        if !読み戻し要求 {
            return Ok(描画方式::通常);
        }
        if !self.フレーム構成.含む(フレーム段階::読み戻し) {
            return Err(レンダラーエラー::読み戻し段階なし);
        }
        let バッファ = self
            .読み戻しバッファ
            .as_ref()
            .unwrap_or_else(|| panic!("読み戻し要求時に読み戻しバッファが未確保だった"));
        Ok(描画方式::読み戻し {
            バッファ: バッファ.handle
        })
    }
}
