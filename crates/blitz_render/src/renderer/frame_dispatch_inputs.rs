//! フレーム送信に渡す画像、提示先、同期プリミティブをレンダラー資源から組み立てる。
//! 提示側のハンドルは`取得済み提示`が運ぶ値だけを読む。ここで提示資源へ触り直さないことで、
//! 取得の直前に済ませた提示状態の判別より後にハンドルを読む経路が生まれない。

use super::frame_progress::フレームスロット資源;
use super::presentation::取得済み提示;
use super::レンダラー;
use crate::vulkan::frame::{フレーム画像一式, 同期入力, 提示先};
use crate::vulkan::post_process::ポスト処理一式;

impl レンダラー {
    pub(super) fn 提示先を組み立てる(&self, 取得済み: &取得済み提示, 提示id: Option<u64>) -> 提示先<'_> {
        提示先 {
            loader: self.環境.swapchain_loader(),
            swapchain: 取得済み.スワップチェーン(),
            画像添字: 取得済み.画像添字(),
            提示id,
        }
    }

    pub(super) fn 同期入力を組み立てる(
        &self, スロット資源: &フレームスロット資源, 取得済み: &取得済み提示
    ) -> 同期入力 {
        同期入力 {
            取得セマフォ: スロット資源.取得セマフォ,
            提示セマフォ: 取得済み.提示セマフォ(),
            描画完了フェンス: スロット資源.フェンス,
        }
    }

    pub(super) fn フレーム画像一式を組み立てる(&self, 取得済み: &取得済み提示) -> フレーム画像一式 {
        let 提示 = 取得済み.画像組();
        フレーム画像一式 {
            スワップチェーン画像: 提示.スワップチェーン画像,
            スワップチェーンビュー: 提示.スワップチェーンビュー,
            深度画像: 提示.深度画像,
            深度ビュー: 提示.深度ビュー,
            シャドウマップ画像: self.シャドウマップ.画像,
            シャドウマップビュー: self.シャドウマップ.画像ビュー,
            // 同じ`Option`から2つを取り出すため、片方だけが`Some`になる組み合わせを作れない。
            hdr: self.ポスト処理.as_ref().map(ポスト処理一式::hdr画像組),
            ブルーム: self.ポスト処理.as_ref().map(ポスト処理一式::ブルーム画像を作る),
        }
    }
}
