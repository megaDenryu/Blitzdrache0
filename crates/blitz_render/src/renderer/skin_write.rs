//! スキン行列の毎フレーム書き込み(判断44)。
//! 触れるフィールドは`スキニング`と`環境`に限る。不変条件として`スキニング`の有無とフレーム描画入力のスキン行列の有無は常に一致し、不一致は型付きエラーにする。

use super::レンダラー;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::vulkan::sync::フレームスロット添字;

impl レンダラー {
    /// 前提: 呼び出しはこのスロットのフェンス待ち後(判断24のUBO書き込みと同じ規律)。
    pub(super) fn スキン行列を書き込む(
        &self,
        フレーム添字: フレームスロット添字,
        入力: &フレーム描画入力,
    ) -> Result<(), レンダラーエラー> {
        match (&self.スキニング, &入力.スキン行列一覧) {
            (Some(スキニング), Some(行列一覧)) => スキニング.行列を書き込む(self.環境.device(), フレーム添字, 行列一覧),
            (None, None) => Ok(()),
            (Some(_), None) => Err(レンダラーエラー::スキン行列不一致(
                "スキン付きシーンなのにスキン行列が未指定".to_string(),
            )),
            (None, Some(_)) => Err(レンダラーエラー::スキン行列不一致(
                "スキン無しシーンにスキン行列が指定された".to_string(),
            )),
        }
    }
}
