//! スキン行列の毎フレーム書き込み(判断44)。スキンメッシュの有無と入力の有無の一致検証を含む。
//! `draw_execute`の行数分割のためだけに切り出した内部ヘルパー。

use super::レンダラー;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;

impl レンダラー {
    /// 前提: 呼び出しはこのスロットのフェンス待ち後(判断24のUBO書き込みと同じ規律)。
    pub(super) fn スキン行列を書き込む(
        &self, フレーム添字: usize, 入力: &フレーム描画入力
    ) -> Result<(), レンダラーエラー> {
        match (&self.スキニング, &入力.スキン行列一覧) {
            (Some(スキニング), Some(行列一覧)) => スキニング.行列を書き込む(&self.device, フレーム添字, 行列一覧),
            (None, None) => Ok(()),
            (Some(_), None) => Err(レンダラーエラー::スキン行列不一致(
                "スキン付きシーンなのにスキン行列が未指定".to_string(),
            )),
            (None, Some(_)) => Err(レンダラーエラー::スキン行列不一致(
                "スキン無しシーンにスキン行列が指定された".to_string(),
            )),
        }
    }
}
