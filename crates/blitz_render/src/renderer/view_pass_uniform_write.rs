//! ビュー・シーンパス定数の内容を組み立てる工程。受け取るのは描画視点・ビュー射影行列・組み立て済みの多段一式・
//! 1フレームの分解済み照明入力、返すのはGPUへ書ける定数内容である。レンダラーの状態には触れない。
//!
//! カメラ位置と点光源位置は焼いた値でなく、毎フレームここでカメラ大域原点を引いて組み立てる。
//! 照明の値を公開の`ライティング入力`から直に読まないのは、GPUへの梱包が分解形だけを受け取る境界だからである
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「現行ライティング入力の改鋳(段1で行う)」)。

use blitz_math::大域ワールド位置;

use crate::cascade::多段一式;
use crate::error::レンダラーエラー;
use crate::frame_lighting::{フレーム照明入力, 直接光入力, 間接照明入力};
use crate::view_input::描画視点;
use crate::vulkan::uniform::ビューとシーンパスの定数内容;

pub(super) fn 組み立てる(
    照明: &フレーム照明入力,
    視点: &描画視点,
    ビュー射影行列: &[[f32; 4]; 4],
    多段: &多段一式,
) -> Result<ビューとシーンパスの定数内容, レンダラーエラー> {
    let 直接光入力::固定 { 方向光, 点光源 } = 照明.直接光();
    let 間接照明入力::定数近似(環境光) = 照明.間接照明();
    let 原点 = 視点.カメラ大域原点();
    Ok(ビューとシーンパスの定数内容 {
        ビュー射影行列: *ビュー射影行列,
        カメラ相対位置: 大域位置をgpu境界配列にする(視点.カメラ大域位置(), 原点)?,
        カメラ前方: 多段.カメラ前方(),
        方向光方向: 方向光.方向(),
        方向光色: 方向光.色(),
        方向光強度: 方向光.強度(),
        点光源位置: 大域位置をgpu境界配列にする(点光源.位置(), 原点)?,
        点光源色: 点光源.色(),
        点光源強度: 点光源.強度(),
        環境光係数: 環境光.値(),
        ライティング有効: 照明.有効性().有効か(),
    })
}

/// GPU境界(生型境界): カメラ大域原点を引いてからf32の生値へ戻す。f64での減算が精度を守る唯一の境界である
/// (数学DDD。参照: CLAUDE.md「型安全性」)。
fn 大域位置をgpu境界配列にする(
    位置: 大域ワールド位置, カメラ大域原点: 大域ワールド位置
) -> Result<[f32; 3], レンダラーエラー> {
    let 相対 = 位置.カメラ相対へ変換する(カメラ大域原点)?;
    Ok([相対.x().値(), 相対.y().値(), 相対.z().値()])
}
