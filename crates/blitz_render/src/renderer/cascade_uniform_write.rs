//! 多段影定数の内容を組み立てる工程。受け取るのはフレーム描画入力・組み立て済みの多段一式・カメラ大域原点、
//! 返すのはGPUへ書ける定数内容である。レンダラーの状態には触れない。
//!
//! 距離区分ごとのライトビュー射影は焼いた値でなく、毎フレームここでカメラ大域原点を引いて組み立てる。

use blitz_math::大域ワールド位置;

use crate::cascade::{多段一式, 距離区分数, 距離区分番号};
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::vulkan::shadow_map;
use crate::vulkan::uniform::多段影定数内容;

pub(super) fn 組み立てる(
    入力: &フレーム描画入力<'_>,
    多段: &多段一式,
    原点: 大域ワールド位置,
) -> Result<多段影定数内容, レンダラーエラー> {
    Ok(多段影定数内容 {
        距離区分のライトビュー射影行列: 距離区分ごとの行列を作る(多段, 原点)?,
        距離区分の分割深度: 多段.分割深度().map(|深度| 深度.値()),
        距離区分の遷移幅: 多段.遷移幅().map(|幅| 幅.値()),
        影を落とす: 入力.ライティング.影を落とすか(),
        距離区分を可視化する: 入力.距離区分を可視化する,
        シャドウマップのテクセル尺度: shadow_map::テクセル尺度(),
    })
}

/// 距離区分ごとのライトビュー射影を、シャドウ記録・シーンのPCF・ライト視錐台の導出が共有する1つの構築結果から取り出す。
fn 距離区分ごとの行列を作る(
    多段: &多段一式,
    原点: 大域ワールド位置,
) -> Result<[[[f32; 4]; 4]; 距離区分数], レンダラーエラー> {
    let mut 行列一覧 = [[[0.0_f32; 4]; 4]; 距離区分数];
    for 番号 in 距離区分番号::全距離区分() {
        行列一覧[番号.添字()] = 多段.距離区分のライトビュー射影(番号, 原点)?.gpu境界用列優先配列();
    }
    Ok(行列一覧)
}
