//! 毎フレームの描画入力作業領域の充填と受け渡し。描画対象資源一覧を走査し、対象1つにつきジオメトリ入力とシャドウ描画入力を1件ずつ積む。
//! 注意: 積む前に必ず空にするため、2本の作業領域の要素数は常に描画対象資源一覧の要素数と一致し、そこから引くディスクリプタセット添字も確保済みの範囲に収まる。

use ash::vk;

use super::シーン描画資源;
use crate::vulkan::frame::{シャドウ描画入力, ジオメトリ入力, 描画対象入力};
use crate::vulkan::sync::フレームスロット添字;

/// 作業領域の中身のうち、描画対象資源の外から与える値。パイプラインは束の外(レンダラー)が保持するためここで受け取る。
pub(in crate::renderer) struct 作業領域更新入力 {
    pub(in crate::renderer) フレーム添字: フレームスロット添字,
    /// スキン付きシーンでの先頭描画対象の頂点バッファ差し替え先(判断44の既存契約)。スキン無しなら`None`。
    pub(in crate::renderer) スキン済み頂点バッファ: Option<vk::Buffer>,
    pub(in crate::renderer) シーンlayout: vk::PipelineLayout,
    pub(in crate::renderer) シャドウpipeline: vk::Pipeline,
    pub(in crate::renderer) シャドウlayout: vk::PipelineLayout,
}

impl シーン描画資源 {
    pub(in crate::renderer) fn 作業領域を更新する(&mut self, 入力: &作業領域更新入力) {
        self.ジオメトリ入力作業領域.clear();
        self.シャドウ入力作業領域.clear();
        for (添字, 資源) in self.描画対象資源一覧.iter().enumerate() {
            // スキニングはシーンの先頭対象だけへ適用する(判断44の既存契約)。
            let 頂点バッファ = if 添字 == 0 {
                入力.スキン済み頂点バッファ.unwrap_or(資源.ジオメトリ.頂点バッファ)
            } else {
                資源.ジオメトリ.頂点バッファ
            };
            let ディスクリプタセット = self.ディスクリプタ.set(添字, 入力.フレーム添字);
            self.ジオメトリ入力作業領域.push(ジオメトリ入力 {
                頂点バッファ,
                インデックスバッファ: 資源.ジオメトリ.インデックスバッファ,
                インデックス数: 資源.ジオメトリ.インデックス数,
                layout: 入力.シーンlayout,
                ディスクリプタセット,
            });
            self.シャドウ入力作業領域.push(シャドウ描画入力 {
                pipeline: 入力.シャドウpipeline,
                layout: 入力.シャドウlayout,
                頂点バッファ,
                インデックスバッファ: 資源.ジオメトリ.インデックスバッファ,
                インデックス数: 資源.ジオメトリ.インデックス数,
                ディスクリプタセット,
            });
        }
    }

    /// 前提: 同じフレームで`作業領域を更新する`を済ませてから呼ぶ(中身は前フレームの残りではなく今フレームの内容である必要がある)。
    pub(in crate::renderer) fn 描画対象入力を作る(&self) -> 描画対象入力<'_> {
        描画対象入力 {
            ジオメトリ: &self.ジオメトリ入力作業領域,
            シャドウ: &self.シャドウ入力作業領域,
        }
    }
}
