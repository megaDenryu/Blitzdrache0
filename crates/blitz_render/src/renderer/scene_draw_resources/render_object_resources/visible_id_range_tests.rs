//! 可視ID列が全個体の並べ替えであることの検査を境界値で確かめる。長さの一致は「シャドウパスが全個体を描く」
//! 不変条件の担保であり、可視個体だけへ縮んだ列がここで止まることを見る。
//! 値の側は、個体数-1が最後の個体を指す正しい添字、個体数そのものが1つ外側、u32::MAXが極端な破れである。
//! 重複の側は、長さと値の両方を満たしながら個体を落とす列がここで止まることと、同じ検査器を続けて使っても
//! 前のフレームの記録が次のフレームの判定へ漏れないことを見る。

use super::visible_id_range::全個体の並べ替え検査;
use crate::visible_instance_selection::可視ID列エラー;

fn 検査する(可視id列: &[u32], 個体数: u32) -> Result<(), 可視ID列エラー> {
    全個体の並べ替え検査::生成する(個体数).検査する(可視id列)
}

#[test]
fn 全個体を並べ替えた列を受理する() {
    assert_eq!(検査する(&[0, 1, 2, 3], 4), Ok(()));
    assert_eq!(検査する(&[2, 0, 3, 1], 4), Ok(()));
    assert_eq!(検査する(&[0], 1), Ok(()));
}

/// 可視個体だけへ縮んだ列は、シャドウパスが個体を落とすことを意味するため受理しない。
#[test]
fn 個体数より短い列を拒否する() {
    assert_eq!(
        検査する(&[0, 1], 4),
        Err(可視ID列エラー::列の長さ不一致 {
            列の長さ: 2, 個体数: 4
        })
    );
    assert_eq!(
        検査する(&[], 1),
        Err(可視ID列エラー::列の長さ不一致 {
            列の長さ: 0, 個体数: 1
        })
    );
}

#[test]
fn 個体数より長い列を拒否する() {
    assert_eq!(
        検査する(&[0, 1, 2], 2),
        Err(可視ID列エラー::列の長さ不一致 {
            列の長さ: 3, 個体数: 2
        })
    );
}

#[test]
fn 個体数そのものを指す列を拒否する() {
    assert_eq!(検査する(&[0, 1, 2, 4], 4), Err(可視ID列エラー::個体数外の可視ID { 可視id: 4, 個体数: 4 }));
}

#[test]
fn 極端に大きなidを拒否する() {
    assert_eq!(
        検査する(&[0, u32::MAX], 2),
        Err(可視ID列エラー::個体数外の可視ID {
            可視id: u32::MAX, 個体数: 2
        })
    );
}

/// 個体を1体も持たない対象へは空の列だけが対応する。
#[test]
fn 個体数0の対象は空の列だけを受理する() {
    assert_eq!(検査する(&[], 0), Ok(()));
    assert_eq!(
        検査する(&[0], 0),
        Err(可視ID列エラー::列の長さ不一致 {
            列の長さ: 1, 個体数: 0
        })
    );
}

/// 長さも値も条件を満たすが、個体3がどちらのパスからも描かれず個体0が二重に描かれる列である。
#[test]
fn 重複を1件含む列を拒否する() {
    assert_eq!(検査する(&[0, 0, 1, 2], 4), Err(可視ID列エラー::重複する可視ID { 可視id: 0 }));
}

#[test]
fn 全要素が同じ列を拒否する() {
    assert_eq!(検査する(&[1, 1, 1, 1], 4), Err(可視ID列エラー::重複する可視ID { 可視id: 1 }));
}

/// 既出記録は読込時に一度だけ確保して使い回すため、前のフレームの記録が次のフレームで重複と誤判定されないことを見る。
#[test]
fn 同じ検査器で同じ列を続けて受理する() {
    let 検査 = 全個体の並べ替え検査::生成する(4);
    assert_eq!(検査.検査する(&[0, 1, 2, 3]), Ok(()));
    assert_eq!(検査.検査する(&[3, 2, 1, 0]), Ok(()));
    assert_eq!(検査.検査する(&[0, 0, 1, 2]), Err(可視ID列エラー::重複する可視ID { 可視id: 0 }));
    assert_eq!(検査.検査する(&[0, 1, 2, 3]), Ok(()));
}
