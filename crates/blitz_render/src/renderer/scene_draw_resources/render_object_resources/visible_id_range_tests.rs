//! 可視ID列が全個体の並べ替えであることの検査を境界値で確かめる。長さの一致は「シャドウパスが全個体を描く」
//! 不変条件の担保であり、可視個体だけへ縮んだ列がここで止まることを見る。
//! 値の側は、個体数-1が最後の個体を指す正しい添字、個体数そのものが1つ外側、u32::MAXが極端な破れである。

use super::visible_id_range::全個体の並べ替えかを検査する;
use crate::visible_instance_selection::可視ID列エラー;

#[test]
fn 全個体を並べ替えた列を受理する() {
    assert_eq!(全個体の並べ替えかを検査する(&[0, 1, 2, 3], 4), Ok(()));
    assert_eq!(全個体の並べ替えかを検査する(&[2, 0, 3, 1], 4), Ok(()));
    assert_eq!(全個体の並べ替えかを検査する(&[0], 1), Ok(()));
}

/// 可視個体だけへ縮んだ列は、シャドウパスが個体を落とすことを意味するため受理しない。
#[test]
fn 個体数より短い列を拒否する() {
    assert_eq!(
        全個体の並べ替えかを検査する(&[0, 1], 4),
        Err(可視ID列エラー::列の長さ不一致 {
            列の長さ: 2, 個体数: 4
        })
    );
    assert_eq!(
        全個体の並べ替えかを検査する(&[], 1),
        Err(可視ID列エラー::列の長さ不一致 {
            列の長さ: 0, 個体数: 1
        })
    );
}

#[test]
fn 個体数より長い列を拒否する() {
    assert_eq!(
        全個体の並べ替えかを検査する(&[0, 1, 2], 2),
        Err(可視ID列エラー::列の長さ不一致 {
            列の長さ: 3, 個体数: 2
        })
    );
}

#[test]
fn 個体数そのものを指す列を拒否する() {
    assert_eq!(
        全個体の並べ替えかを検査する(&[0, 1, 2, 4], 4),
        Err(可視ID列エラー::個体数外の可視ID { 可視id: 4, 個体数: 4 })
    );
}

#[test]
fn 極端に大きなidを拒否する() {
    assert_eq!(
        全個体の並べ替えかを検査する(&[0, u32::MAX], 2),
        Err(可視ID列エラー::個体数外の可視ID {
            可視id: u32::MAX, 個体数: 2
        })
    );
}

/// 個体を1体も持たない対象へは空の列だけが対応する。
#[test]
fn 個体数0の対象は空の列だけを受理する() {
    assert_eq!(全個体の並べ替えかを検査する(&[], 0), Ok(()));
    assert_eq!(
        全個体の並べ替えかを検査する(&[0], 0),
        Err(可視ID列エラー::列の長さ不一致 {
            列の長さ: 1, 個体数: 0
        })
    );
}
