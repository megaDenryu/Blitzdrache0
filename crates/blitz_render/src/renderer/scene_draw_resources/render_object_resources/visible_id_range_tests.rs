//! 可視ID列の値と個体数の突き合わせを境界値で検査する。個体数-1は最後の個体を指す正しい添字であり、
//! 個体数そのものは1つ外側、u32::MAXは呼び出し元が壊れた値を渡した場合の極端である。
//! 空の列は可視0の選択として本番で毎フレーム起こるため、受理側に含める。

use super::visible_id_range::個体数の内側かを検査する;
use crate::visible_instance_selection::可視ID列エラー;

#[test]
fn 個体数の内側を指す列を受理する() {
    assert_eq!(個体数の内側かを検査する(&[], 4), Ok(()));
    assert_eq!(個体数の内側かを検査する(&[0, 1, 2, 3], 4), Ok(()));
    assert_eq!(個体数の内側かを検査する(&[3], 4), Ok(()));
}

#[test]
fn 個体数そのものを指す列を拒否する() {
    assert_eq!(
        個体数の内側かを検査する(&[4], 4),
        Err(可視ID列エラー::個体数外の可視ID { 可視id: 4, 個体数: 4 })
    );
    assert_eq!(
        個体数の内側かを検査する(&[0, 2, 4], 4),
        Err(可視ID列エラー::個体数外の可視ID { 可視id: 4, 個体数: 4 })
    );
}

#[test]
fn 極端に大きなidを拒否する() {
    assert_eq!(
        個体数の内側かを検査する(&[u32::MAX], 2),
        Err(可視ID列エラー::個体数外の可視ID {
            可視id: u32::MAX, 個体数: 2
        })
    );
}

/// 個体を1体も持たない対象へは、どのIDも書き込めない。
#[test]
fn 個体数0の対象はどのidも拒否する() {
    assert_eq!(個体数の内側かを検査する(&[], 0), Ok(()));
    assert_eq!(
        個体数の内側かを検査する(&[0], 0),
        Err(可視ID列エラー::個体数外の可視ID { 可視id: 0, 個体数: 0 })
    );
}
