//! 可視ID列の中身がその描画対象の個体と整合していることの判定。受け取るのはそのフレームの可視ID列と
//! パス別区間の配置、返すのは受理か型付きエラーかである。バッファには一切触れない。
//!
//! 検査は3つある。段別個体数の合計が個体数と一致すること、各値が個体数の内側を指すこと、
//! 1つのパスの区間の中に同じ値が2回現れないことである。
//! 合計の検査は「どの段からも漏れた個体が無いこと」の担保である。段はその対象の全個体を分割したものであり、
//! 合計が欠ければその個体はどのパスにも描かれない。列そのものの長さは可視な個体だけを並べた値になったため、
//! 長さと個体数を比べる旧来の検査(列が全個体の並べ替えであること)はこの合計の検査が引き継いだ。
//! 値の検査は、シーンとシャドウの頂点シェーダーがこの添字で個体変換のストレージバッファを参照するため、
//! 個体数以上のIDを書き込むとGPUが確保の外を読むことによる。
//! 重複の検査をパスごとに行うのは、帯をまたいだ同じIDの重複が正しい影に必要である一方、同じパスの区間の中の重複は
//! その個体を二重に描いて別の個体を落としたことを意味するためである。重複を見る既出記録は`seen_record`が持つ。
//! 区間そのものの配置(正典順に隙間なく並ぶこと)は`visible_instance_selection`の`interval_layout`が見ており、
//! 値を個体数と突き合わせられるのはこの書き込み境界だけである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の帯別区間(4区分並べの後継)」

use super::seen_record::既出記録;
use crate::visible_instance_selection::{パス別描画範囲, 可視ID列エラー, 可視パス, 段別描画範囲};

pub(super) struct 可視ID列の内容検査 {
    個体数: u32,
    記録: 既出記録,
}

impl 可視ID列の内容検査 {
    /// 束の読込時に1回だけ呼ぶ。以後この型は確保を行わない。
    pub(super) fn 生成する(個体数: u32) -> Self {
        Self {
            個体数,
            記録: 既出記録::生成する(個体数),
        }
    }

    pub(super) fn 個体数(&self) -> u32 {
        self.個体数
    }

    /// 途中で拒否したときに記録が進行中の世代のまま残るが、次の検査は世代を進めてから読むため影響しない。
    pub(super) fn 検査する(&self, 可視id列: &[u32], 段範囲一覧: &[段別描画範囲]) -> Result<(), 可視ID列エラー> {
        self.段別個体数の合計を検査する(段範囲一覧)?;
        for パス in 可視パス::全パス() {
            let 世代 = self.記録.世代を進める();
            for 段 in 段範囲一覧 {
                for 可視id in 区間を切り出す(可視id列, 段.パス(パス))?.iter().copied() {
                    match self.記録.初めて見たか(可視id, 世代) {
                        Some(true) => {}
                        Some(false) => return Err(可視ID列エラー::パス内で重複する可視ID { パス, 可視id }),
                        None => {
                            return Err(可視ID列エラー::個体数外の可視ID {
                                可視id, 個体数: self.個体数
                            });
                        }
                    }
                }
            }
        }
        Ok(())
    }

    /// 段はその対象の全個体を分割したものであるから、合計は常に個体数に等しい。
    /// 加算が溢れた組み合わせはu32の上限として扱い、個体数と一致しない値として拒む。
    fn 段別個体数の合計を検査する(&self, 段範囲一覧: &[段別描画範囲]) -> Result<(), 可視ID列エラー> {
        let 合計 = 段範囲一覧
            .iter()
            .map(|段| 段.個体数())
            .try_fold(0u32, |累計, 個体数| 累計.checked_add(個体数))
            .unwrap_or(u32::MAX);
        if 合計 == self.個体数 {
            return Ok(());
        }
        Err(可視ID列エラー::段別個体数の合計不一致 {
            合計, 個体数: self.個体数
        })
    }
}

/// 区間が列の内側を指していることは`interval_layout`が済ませているが、値を読む地点でも確かめる。
/// ここで読み外すことはGPUへ書く直前の実装の誤りであり、無言で切り詰めてはならない。
fn 区間を切り出す(可視id列: &[u32], 区間: パス別描画範囲) -> Result<&[u32], 可視ID列エラー> {
    let 開始 = usize::try_from(区間.開始()).unwrap_or(usize::MAX);
    let 件数 = usize::try_from(区間.描画数()).unwrap_or(usize::MAX);
    開始
        .checked_add(件数)
        .and_then(|終端| 可視id列.get(開始..終端))
        .ok_or(可視ID列エラー::区間が範囲外 {
            開始,
            列の長さ: 可視id列.len(),
        })
}
