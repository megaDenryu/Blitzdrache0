//! 束の共有列への書き込み要求を、パスごとの可視の有無で長さが変わる列と、それ以外の内容で検査する。
//! 単一個体のインスタンス群も可視判定と段選択の対象になるため、値0だけの列は本番で毎フレーム渡る。

use super::shared_single_column::書き込み要求を受理する;
use crate::visible_instance_selection::{可視ID列を読むパス数, 可視ID列エラー};

/// 全パスへ現れるフレームはパス数ぶんの件数、一部のパスだけのフレームはその件数になる。どちらも中身は値0だけである。
#[test]
fn 値0だけを並べた列を受理する() {
    assert_eq!(書き込み要求を受理する(&[0]), Ok(()));
    assert_eq!(書き込み要求を受理する(&[0, 0]), Ok(()));
    assert_eq!(書き込み要求を受理する(&[0; 可視ID列を読むパス数]), Ok(()));
}

/// どのパスからも見えないフレームでは区間がすべて空になり、列そのものが空になる。
#[test]
fn 空の列を受理する() {
    assert_eq!(書き込み要求を受理する(&[]), Ok(()));
}

#[test]
fn 値0以外を含む列を拒否する() {
    assert_eq!(書き込み要求を受理する(&[1]), Err(可視ID列エラー::書き込み先なし));
    assert_eq!(書き込み要求を受理する(&[0, 1]), Err(可視ID列エラー::書き込み先なし));
}

/// 単一個体の対象が読む共有列はパス数ぶんの件数しか持たないため、それを超える長さの要求は受け皿が無い。
#[test]
fn 容量を超える長さの列を拒否する() {
    assert_eq!(
        書き込み要求を受理する(&[0; 可視ID列を読むパス数 + 1]),
        Err(可視ID列エラー::書き込み先なし)
    );
}
