//! 束の共有列への書き込み要求を、可視0・可視1・不正IDの3つで検査する。
//! 単一個体のインスタンス群は可視判定の対象になるため、可視0と可視1はどちらも本番で毎フレーム起こる。

use super::shared_single_column::書き込み要求を受理する;
use crate::visible_instance_selection::可視ID列エラー;

#[test]
fn 可視0の選択を受理する() {
    assert_eq!(書き込み要求を受理する(&[]), Ok(()));
}

#[test]
fn 唯一の個体を指す可視1の選択を受理する() {
    assert_eq!(書き込み要求を受理する(&[0]), Ok(()));
}

#[test]
fn 共有列に無いidを含む選択を拒否する() {
    assert_eq!(書き込み要求を受理する(&[1]), Err(可視ID列エラー::書き込み先なし));
    assert_eq!(書き込み要求を受理する(&[0, 0]), Err(可視ID列エラー::書き込み先なし));
}
