//! 束の共有列への書き込み要求を、唯一の個体を並べた列と、それ以外の内容の3つで検査する。
//! 単一個体のインスタンス群も可視判定と段選択の対象になるため、値0だけの列は本番で毎フレーム渡る。

use super::shared_single_column::書き込み要求を受理する;
use crate::visible_instance_selection::可視ID列エラー;

#[test]
fn 唯一の個体を並べた列を受理する() {
    assert_eq!(書き込み要求を受理する(&[0]), Ok(()));
}

/// 可視ID列は全個体の並べ替えであり、単一個体の対象で空になることはない。
#[test]
fn 空の列を拒否する() {
    assert_eq!(書き込み要求を受理する(&[]), Err(可視ID列エラー::書き込み先なし));
}

#[test]
fn 共有列に無い内容の列を拒否する() {
    assert_eq!(書き込み要求を受理する(&[1]), Err(可視ID列エラー::書き込み先なし));
    assert_eq!(書き込み要求を受理する(&[0, 0]), Err(可視ID列エラー::書き込み先なし));
}
