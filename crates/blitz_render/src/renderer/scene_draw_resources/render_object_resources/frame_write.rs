//! 描画対象1つぶんの、そのフレームぶんのGPUへの書き込みの局面。呼ばれるのは描画発行を積む走査の中でフレームごとに1回ずつであり、
//! 束の読込時に1度だけ走る確保とは呼び出し頻度が違う。触れるのは可視ID列と個体変換の2つの置き場だけである。
//!
//! 前提: このフレームスロットの描画完了フェンスは待機済みであり、GPUはどちらのバッファも読んでいない
//! (待機は`renderer/draw_execute/prepare.rs`が行う)。

use crate::error::{フレーム入力不一致エラー, レンダラーエラー};
use crate::frame_input::動く個体の大域位置の指定;
use crate::visible_instance_selection::個体描画計画;
use crate::vulkan::sync::フレームスロット添字;

use super::描画対象資源;

impl 描画対象資源 {
    /// そのフレームに描く個体の添字をパス別・段別の並びで書く。可視個体選択を持たない対象へは呼ばない。
    /// 書き込む前に中身を確かめるのは、この型が対象の個体数を持つ唯一の書き込み境界だからである。
    /// 段別個体数の合計が個体数と一致することが、どのパスからも漏れた個体が無いことの担保になる。
    pub(in crate::renderer::scene_draw_resources) fn 可視id列を書き込む(
        &self,
        device: &ash::Device,
        フレーム添字: フレームスロット添字,
        計画: 個体描画計画<'_>,
    ) -> Result<(), レンダラーエラー> {
        self.内容検査.検査する(計画.id列, 計画.段範囲一覧)?;
        self.可視id列.書き込む(device, フレーム添字, 計画.id列)
    }

    /// そのフレームの動く個体の位置を書き込む。大域位置をこの対象の描画の基準原点からの相対へ狭めるのはここであり、
    /// カメラ相対への変換は描画発行のプッシュ定数が運ぶ基準原点が別に行う。
    pub(in crate::renderer::scene_draw_resources) fn 動く個体の位置を書き込む(
        &self,
        device: &ash::Device,
        フレーム添字: フレームスロット添字,
        指定: 動く個体の大域位置の指定,
    ) -> Result<(), レンダラーエラー> {
        let 相対位置 = 指定
            .大域位置
            .基準原点からの相対位置へ狭める(self.大域の基準原点)
            .map_err(フレーム入力不一致エラー::動く個体の位置が基準原点から遠すぎる)?;
        self.個体変換.動く個体の位置を書き込む(device, フレーム添字, 指定.個体添字, 相対位置)
    }
}
