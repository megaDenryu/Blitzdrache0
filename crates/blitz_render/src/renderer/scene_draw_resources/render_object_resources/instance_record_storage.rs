//! 1つの描画対象が個体レコードをどこへ持つかを表す判別共用体と、その確保。
//! 触れるのは自分が確保したバッファだけであり、ディスクリプタが指す参照を返す読み取りと、動く個体の書き込みに閉じる。
//!
//! 動く個体を1体も宣言していない対象が静的な枝のままであることが、既存の入口の判定値が変わらないことの根拠である。
//! 静的な枝はデバイスローカルの1本を読込時に一度だけ書き、毎フレームの書き込みもフレームスロットぶんの確保も持たない。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断5: 動くオブジェクトはゲーム状態が正本であり、描画へは毎フレーム供給する」

use ash::vk;
use blitz_math::{ワールド, 位置};

use crate::error::{フレーム入力不一致エラー, レンダラーエラー};
use crate::vulkan::instance_transform::content::個体変換内容;
use crate::vulkan::instance_transform::{個体レコード参照, 個体変換バッファ, 動く個体の変換バッファ};
use crate::vulkan::sync::フレームスロット添字;
use crate::vulkan::tracked_device::GPUデバイス;
use crate::vulkan::transfer::転送実行環境;

pub(super) enum 個体レコードの置き場 {
    /// 動く個体を1体も持たない対象。読込時に一度だけ書いたデバイスローカルの1本を全フレームスロットが読む。
    読込時に一度だけ書いた静的バッファ(個体変換バッファ),
    /// 動く個体を持つ対象。フレームスロットごとのホスト可視バッファを持ち、動く個体の位置を毎フレーム書き換える。
    毎フレーム書き込むスロット別バッファ(動く個体の変換バッファ),
}

impl 個体レコードの置き場 {
    pub(super) fn 生成する(
        device: &GPUデバイス,
        メモリプロパティ: &vk::PhysicalDeviceMemoryProperties,
        転送環境: &転送実行環境,
        内容一覧: &[個体変換内容],
        動く個体添字一覧: &[u32],
    ) -> Result<Self, レンダラーエラー> {
        if 動く個体添字一覧.is_empty() {
            return Ok(Self::読込時に一度だけ書いた静的バッファ(個体変換バッファ::生成する(
                device,
                メモリプロパティ,
                転送環境,
                内容一覧,
            )?));
        }
        Ok(Self::毎フレーム書き込むスロット別バッファ(
            動く個体の変換バッファ::生成する(device, メモリプロパティ, 内容一覧, 動く個体添字一覧)?,
        ))
    }

    pub(super) fn 参照(&self) -> 個体レコード参照 {
        match self {
            Self::読込時に一度だけ書いた静的バッファ(バッファ) => バッファ.参照(),
            Self::毎フレーム書き込むスロット別バッファ(バッファ) => バッファ.参照(),
        }
    }

    /// 動く個体を1体も宣言していない対象への位置指定は、無言で捨てず型付きエラーで拒む。
    /// 捨てると、供給しているのに動かない状態が絵にしか現れない。
    pub(super) fn 動く個体の位置を書き込む(
        &self,
        device: &ash::Device,
        フレーム添字: フレームスロット添字,
        個体添字: u32,
        基準原点からの相対位置: 位置<ワールド>,
    ) -> Result<(), レンダラーエラー> {
        match self {
            Self::読込時に一度だけ書いた静的バッファ(_) => {
                Err(フレーム入力不一致エラー::動く個体を持たない描画対象への位置指定 { 個体添字 }.into())
            }
            Self::毎フレーム書き込むスロット別バッファ(バッファ) => {
                バッファ.動く個体の位置を書き込む(device, フレーム添字, 個体添字, 基準原点からの相対位置)
            }
        }
    }

    pub(super) fn 破棄する(&self, device: &GPUデバイス) {
        match self {
            Self::読込時に一度だけ書いた静的バッファ(バッファ) => バッファ.破棄する(device),
            Self::毎フレーム書き込むスロット別バッファ(バッファ) => バッファ.破棄する(device),
        }
    }
}
