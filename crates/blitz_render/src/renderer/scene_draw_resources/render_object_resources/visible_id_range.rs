//! 可視ID列がその描画対象の全個体の並べ替え(0から個体数-1までを1回ずつ並べた列)であることの判定と、判定が使う既出記録。
//! 受け取るのはそのフレームの可視ID列、返すのは受理か型付きエラーかである。バッファには一切触れない。
//!
//! 検査は3つある。長さが個体数と一致すること、各値が個体数の内側を指すこと、同じ値が2回現れないことである。
//! 長さの検査は「シャドウパスが全個体を描く」という不変条件の担保である。列がシーンパスの可視個体だけへ
//! 縮んでいれば長さが個体数を下回り、ここで止まる(参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」)。
//! 値の検査は、シーンとシャドウの頂点シェーダーがこの添字で個体変換のストレージバッファを参照するため、
//! 個体数以上のIDを書き込むとGPUが確保の外を読むことによる。
//! 重複の検査は、長さと値の2つだけでは列が並べ替えであることを言えないことによる。個体数4に対する`[0, 0, 1, 2]`は
//! 両方を満たしながら個体3をどちらのパスからも落とし、個体0を二重に描く。
//! 区間と段範囲の検査は列の長さしか見ておらず、値そのものを個体数と突き合わせられるのはこの書き込み境界だけである。

use std::cell::Cell;

use crate::visible_instance_selection::可視ID列エラー;

/// まだどの検査でも見ていない個体を表す世代番号。検査の世代は1から始まるため、この値と一致することはない。
const 未検査の世代: u32 = 0;

/// 記録を全消去した直後に使う世代番号。
const 最初の世代: u32 = 1;

pub(super) struct 全個体の並べ替え検査 {
    個体数: u32,
    /// 個体ごとに、最後にその個体を見た検査の世代番号を持つ。件数は常に個体数に等しい。
    /// 要素を`Cell`で持つのは、毎フレームの書き込みが描画対象資源の共有参照から呼ばれるためである。
    最後に見た世代: Vec<Cell<u32>>,
    /// 進行中の検査の世代番号。
    現世代: Cell<u32>,
}

impl 全個体の並べ替え検査 {
    /// 束の読込時に1回だけ呼ぶ。以後この型は確保を行わない。
    pub(super) fn 生成する(個体数: u32) -> Self {
        Self {
            個体数,
            最後に見た世代: (0..個体数).map(|_| Cell::new(未検査の世代)).collect(),
            現世代: Cell::new(未検査の世代),
        }
    }

    pub(super) fn 個体数(&self) -> u32 {
        self.個体数
    }

    /// 途中で拒否したときに記録が進行中の世代のまま残るが、次の検査は世代を進めてから読むため影響しない。
    pub(super) fn 検査する(&self, 可視id列: &[u32]) -> Result<(), 可視ID列エラー> {
        if !usize::try_from(self.個体数).is_ok_and(|数| 数 == 可視id列.len()) {
            return Err(可視ID列エラー::列の長さ不一致 {
                列の長さ: 可視id列.len(),
                個体数: self.個体数,
            });
        }
        let 世代 = self.世代を進める();
        for 可視id in 可視id列.iter().copied() {
            let 記録 = self.記録を参照する(可視id)?;
            if 記録.get() == 世代 {
                return Err(可視ID列エラー::重複する可視ID { 可視id });
            }
            記録.set(世代);
        }
        Ok(())
    }

    /// 記録の件数は個体数に等しいため、参照できないことがそのまま個体数の外を指すことになる。
    fn 記録を参照する(&self, 可視id: u32) -> Result<&Cell<u32>, 可視ID列エラー> {
        usize::try_from(可視id)
            .ok()
            .and_then(|添字| self.最後に見た世代.get(添字))
            .ok_or(可視ID列エラー::個体数外の可視ID {
                可視id, 個体数: self.個体数
            })
    }

    /// 検査の世代を1つ進める。世代で区別するのは、毎フレーム記録を全消去すると検査そのものと同じ大きさの走査が
    /// もう1回増えるためである。全消去は世代がu32を一巡したときにだけ起こる。
    fn 世代を進める(&self) -> u32 {
        let 次 = match self.現世代.get().checked_add(1) {
            Some(値) => 値,
            None => {
                for 記録 in &self.最後に見た世代 {
                    記録.set(未検査の世代);
                }
                最初の世代
            }
        };
        self.現世代.set(次);
        次
    }
}
