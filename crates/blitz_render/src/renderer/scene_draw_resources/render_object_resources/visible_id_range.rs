//! 可視ID列がその描画対象の全個体の並べ替えであることの判定。受け取るのはそのフレームの可視ID列と対象の個体数、
//! 返すのは受理か型付きエラーかである。バッファには一切触れない純粋な判定であり、判定と書き込みを1箇所に混ぜないために分けてある。
//!
//! 検査は2つある。長さが個体数と一致すること、各値が個体数の内側を指すことである。
//! 長さの検査は「シャドウパスが全個体を描く」という不変条件の担保である。列がシーンパスの可視個体だけへ
//! 縮んでいれば長さが個体数を下回り、ここで止まる(参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」)。
//! 値の検査は、シーンとシャドウの頂点シェーダーがこの添字で個体変換のストレージバッファを引くため、
//! 個体数以上のIDを書き込むとGPUが確保の外を読むことによる。区間と段範囲の検査は列の長さしか見ておらず、
//! 値そのものを個体数と突き合わせられるのはこの書き込み境界だけである。

use crate::visible_instance_selection::可視ID列エラー;

pub(super) fn 全個体の並べ替えかを検査する(可視id列: &[u32], 個体数: u32) -> Result<(), 可視ID列エラー> {
    if !usize::try_from(個体数).is_ok_and(|数| 数 == 可視id列.len()) {
        return Err(可視ID列エラー::列の長さ不一致 {
            列の長さ: 可視id列.len(),
            個体数,
        });
    }
    match 可視id列.iter().copied().find(|可視id| *可視id >= 個体数) {
        Some(可視id) => Err(可視ID列エラー::個体数外の可視ID { 可視id, 個体数 }),
        None => Ok(()),
    }
}
