//! 可視ID列の各値がその描画対象の個体数の内側を指すことの判定。受け取るのはそのフレームの可視ID列と対象の個体数、
//! 返すのは受理か型付きエラーかである。バッファには一切触れない純粋な判定であり、判定と書き込みを1箇所に混ぜないために分けてある。
//!
//! シーンの頂点シェーダーは可視ID列から得た添字で個体変換のストレージバッファを引く。可視個体選択の区間の検査は
//! 「選択が可視ID列の内側を指すこと」しか見ておらず、列に入っている値そのものは見ていないため、個体数以上のIDを
//! 書き込むとGPUが確保の外を読む。値を個体数と突き合わせられるのは、対象の個体数を持つこの書き込み境界だけである。

use crate::visible_instance_selection::可視ID列エラー;

pub(super) fn 個体数の内側かを検査する(可視id列: &[u32], 個体数: u32) -> Result<(), 可視ID列エラー> {
    match 可視id列.iter().copied().find(|可視id| *可視id >= 個体数) {
        Some(可視id) => Err(可視ID列エラー::個体数外の可視ID { 可視id, 個体数 }),
        None => Ok(()),
    }
}
