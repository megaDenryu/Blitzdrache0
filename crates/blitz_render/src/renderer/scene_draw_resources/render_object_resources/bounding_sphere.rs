//! 描画対象1つの全個体を覆う球。読み込み時に1度だけ求め、以後変わらない。
//! 触れるのは球の中心と半径だけであり、GPU資源にも毎フレームの入力にも触れない。
//!
//! この球を持つのは、点光源の影の面ごとの描画パスが描く対象を絞るためである。可視ID列の区間を増やさない裁定により、
//! 面ごとの候補は毎フレーム別の経路で求めることになっており、その判定に要る保守的な体積がこれである
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断n」)。
//!
//! 中心はその描画対象の基準原点からの相対で持つ。大きな座標をf32で持たない規律を守るためであり、
//! カメラ相対へ狭めるのは判定を行うフレームの側である。

mod combine;

use blitz_math::{メートル, ローカル, ワールド, 変換};

use crate::vertex::頂点;

/// 描画対象の全個体を覆う球。動く個体を宣言した対象は、読み込み時の変換が毎フレーム書き換わるため球が定まらない。
///
/// `定まった球`は静的な個体変換だけを持つ対象であり、全詳細段の頂点と全個体の配置から求めた球である。
/// `毎フレーム変わるため定まらない`は動く個体を宣言した対象であり、絞りの判定では常に候補として扱う(落とすと影が消えるためである)。
#[derive(Debug, Clone, Copy)]
pub(in crate::renderer::scene_draw_resources) enum 描画対象の境界球 {
    定まった球 {
        中心: [f32; 3], // 基準原点からの相対で表した中心(メートル)
        半径: f32,
    },
    毎フレーム変わるため定まらない,
}

impl 描画対象の境界球 {
    /// 全詳細段の頂点と全個体の変換から求める。動く個体を1件でも宣言した対象は定まらない側にする。
    pub(in crate::renderer::scene_draw_resources) fn 段と個体から求める(
        段別の頂点一覧: &[&[頂点]],
        個体変換一覧: &[変換<ローカル, ワールド>],
        動く個体添字一覧: &[u32],
    ) -> Self {
        if !動く個体添字一覧.is_empty() {
            return Self::毎フレーム変わるため定まらない;
        }
        let 原型の半径 = 段別の頂点一覧
            .iter()
            .flat_map(|段| 段.iter())
            .map(|頂点| combine::長さ(頂点.位置))
            .fold(0.0_f32, f32::max);
        let 個体の球一覧: Vec<([f32; 3], f32)> = 個体変換一覧.iter().map(|変換| combine::個体の球を求める(*変換, 原型の半径)).collect();
        let (中心, 半径) = combine::個体の球をまとめる(&個体の球一覧);
        Self::定まった球 { 中心, 半径 }
    }

    /// 判定に使う中心と半径。定まらない対象は値を持たないため、呼び出し元が常に候補として扱う。
    pub(in crate::renderer::scene_draw_resources) fn 中心と半径(self) -> Option<([f32; 3], メートル)> {
        match self {
            Self::定まった球 { 中心, 半径 } => Some((中心, メートル::生成する(半径))),
            Self::毎フレーム変わるため定まらない => None,
        }
    }
}
