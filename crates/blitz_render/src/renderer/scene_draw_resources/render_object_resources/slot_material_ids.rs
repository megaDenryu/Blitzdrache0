//! 1つの描画対象が材質スロット番号ごとに持つ大域材質ID。触れるのはスロット番号と材質IDの対応だけであり、
//! 段の選択も可視選別もGPU資源も知らない。
//!
//! スロット番号で引けるようにするのは、プリミティブ描画発行が原型の語彙である材質スロット番号で材質を指すためである。
//! 番号を並びの添字で代用しないのは、未使用スロットを許す契約のもとで番号が飛びうるためである。
//! 注意: 保持するのは材質IDだけであり、資源表世代の中でのレコード添字を持たない。添字は世代を作り直すと変わるため、
//! 束のように世代より長生きするものが持つと、旧い添字が新しい表の別の材質を指す
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「材質レコードとテクスチャ台帳」)。

use crate::render_object_material::材質スロット素材一覧;
use crate::vulkan::material_table::大域材質ID;

pub(super) struct スロット別材質ID {
    一覧: Vec<(u32, 大域材質ID)>,
}

impl スロット別材質ID {
    /// 前提: `材質id一覧`は`素材一覧`と同じ並びである(材質資源表への登録がその並びで発番する)。
    pub(super) fn 組み立てる(素材一覧: &材質スロット素材一覧, 材質id一覧: &[大域材質ID]) -> Self {
        assert_eq!(
            素材一覧.件数(),
            材質id一覧.len(),
            "材質スロット素材の件数と発番された材質IDの件数が食い違った"
        );
        let 一覧 = 素材一覧
            .一覧()
            .iter()
            .zip(材質id一覧.iter())
            .map(|(素材, 材質id)| (素材.スロット番号(), *材質id))
            .collect();
        Self { 一覧 }
    }

    /// そのスロット番号の材質ID。持たなければ`None`。走査が線形なのは、件数が1つの原型が持つ材質スロットの数であり、
    /// 作者が1つのメッシュへ割り当てた材質の数と同じ桁に収まるためである。
    pub(super) fn スロット番号で引く(&self, スロット番号: u32) -> Option<大域材質ID> {
        self.一覧.iter().find(|(番号, _)| *番号 == スロット番号).map(|(_, 材質id)| *材質id)
    }
}
