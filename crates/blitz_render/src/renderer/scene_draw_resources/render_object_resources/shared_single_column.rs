//! 束が共有する「値0だけの可視ID列」へ書き込み要求が来たときの受理判定。受け取るのはそのフレームの可視ID列、
//! 返すのは受理か型付きエラーかである。バッファには一切触れない純粋な判定であり、判定と書き込みの両方を1箇所に混ぜないために分けてある。
//!
//! 共有列は生成時に値0の1件だけを書き、以後どの対象も書き換えない。個体が1体だけの対象は可視判定の結果として
//! 「その1体が見えない(可視0)」か「その1体が見える(可視1、添字は0)」しか取り得ず、どちらも共有列の内容と矛盾しない。
//! 可視0のときは描画発行のインスタンス数が0になるため列そのものが読まれず、可視1のときは共有列の値0がそのまま正しい。
//! それ以外のIDを含む選択は呼び出し元の作り方の誤りであり、共有列を書き換えると他の対象まで壊れるため受理しない。

use crate::visible_instance_selection::可視ID列エラー;

/// 単一個体の対象が読む共有列の唯一の要素。
const 共有列の唯一のID: u32 = 0;

pub(super) fn 書き込み要求を受理する(可視id列: &[u32]) -> Result<(), 可視ID列エラー> {
    match 可視id列 {
        [] => Ok(()),
        [唯一] if *唯一 == 共有列の唯一のID => Ok(()),
        _ => Err(可視ID列エラー::書き込み先なし),
    }
}
