//! 束が共有する「値0だけの可視ID列」へ書き込み要求が来たときの受理判定。受け取るのはそのフレームの可視ID列、
//! 返すのは受理か型付きエラーかである。バッファには一切触れない純粋な判定であり、判定と書き込みの両方を1箇所に混ぜないために分けてある。
//!
//! 共有列は生成時に値0だけを容量ぶん(パス数と同じ件数)並べて書き、以後どの対象も書き換えない。
//! 個体が1体だけの対象の可視ID列は、どのパスの区間も唯一の個体を指すか空であるため、値0だけを並べた列にしかならない。
//! 距離区分別の区間ではこの列の長さがパスごとの可視の有無で変わり、5体すべてのパスへ現れるフレームでは5件、
//! どのパスからも見えないフレームでは空になる。どの長さでも共有列の中身と一致するため、書き込みを省いて受理できる。
//! 値0以外を含む選択と、容量を超える長さの選択は呼び出し元の作り方の誤りであり、
//! 共有列を書き換えると他の対象まで壊れるため受理しない。

use crate::visible_instance_selection::{可視ID列を読むパス数, 可視ID列エラー};

/// 単一個体の対象が読む共有列の要素。唯一の個体を指す値である。
const 共有列のID: u32 = 0;

pub(super) fn 書き込み要求を受理する(可視id列: &[u32]) -> Result<(), 可視ID列エラー> {
    if 可視id列.len() <= 可視ID列を読むパス数 && 可視id列.iter().all(|可視id| *可視id == 共有列のID) {
        return Ok(());
    }
    Err(可視ID列エラー::書き込み先なし)
}
