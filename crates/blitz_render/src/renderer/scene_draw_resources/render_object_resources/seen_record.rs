//! 1つのパスの区間の中に同じ個体IDが2回現れないことを見るための既出記録。触れるのは個体ごとの世代番号の列と
//! 進行中の世代だけであり、可視ID列も区間も知らない。
//!
//! 世代番号で区別するのは、パスごとに記録を全消去すると検査そのものと同じ大きさの走査がパス数ぶん増えるためである。
//! 記録は束の読込時に個体数ぶんを一度だけ確保して使い回し、全消去は世代がu32を一巡したときにだけ起こる。
//! 要素を`Cell`で持つのは、毎フレームの書き込みが描画対象資源の共有参照から呼ばれるためである。
//! 検査の世代は1から始まるため、`未検査の世代`と一致することはない。`最後に見た世代`の件数は常に個体数に等しい。
//! `現世代`はパスごとに1つ進めるため、1フレームでパス数ぶん進む。

use std::cell::Cell;

const 未検査の世代: u32 = 0; // まだどの検査でも見ていない個体を表す世代番号
const 最初の世代: u32 = 1; // 記録を全消去した直後に使う世代番号

pub(super) struct 既出記録 {
    最後に見た世代: Vec<Cell<u32>>, // 個体ごとに、最後にその個体を見た検査の世代番号
    現世代: Cell<u32>,              // 進行中の検査の世代番号
}

impl 既出記録 {
    /// 束の読込時に1回だけ呼ぶ。以後この型は確保を行わない。
    pub(super) fn 生成する(個体数: u32) -> Self {
        Self {
            最後に見た世代: (0..個体数).map(|_| Cell::new(未検査の世代)).collect(),
            現世代: Cell::new(未検査の世代),
        }
    }

    /// 新しい世代を始める。同じ世代の中で同じ個体を2回見たときだけ重複になる。
    pub(super) fn 世代を進める(&self) -> u32 {
        let 次 = match self.現世代.get().checked_add(1) {
            Some(値) => 値,
            None => {
                for 記録 in &self.最後に見た世代 {
                    記録.set(未検査の世代);
                }
                最初の世代
            }
        };
        self.現世代.set(次);
        次
    }

    /// その個体をこの世代で初めて見たなら記録して真を返し、すでに見ていたなら偽を返す。
    /// 記録の件数は個体数に等しいため、記録が無いことがそのまま個体数の外を指すことになり、その場合は`None`を返す。
    pub(super) fn 初めて見たか(&self, 可視id: u32, 世代: u32) -> Option<bool> {
        let 記録 = usize::try_from(可視id).ok().and_then(|添字| self.最後に見た世代.get(添字))?;
        if 記録.get() == 世代 {
            return Some(false);
        }
        記録.set(世代);
        Some(true)
    }
}
