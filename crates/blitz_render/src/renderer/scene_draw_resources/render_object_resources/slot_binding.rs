//! 描画対象の材質スロットを、ディスクリプタセットが結ぶ資源の参照へ解決する操作。
//! 触れるのはスロット別材質資源・個体変換バッファ・可視ID列の出どころの3つだけであり、段別ジオメトリと内容検査には触れない。
//!
//! 不変条件: スロット添字の並びはディスクリプタセットの並びと同じである。束の生成が`材質スロット数`の範囲を順に引いて参照の列を作り、
//! 描画発行が`材質スロット番号で添字を引く`で得た添字で同じ並びのセットを選ぶため、2つがずれると別の材質を束ねたまま描画が成立する。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「束縛バックエンドの移行境界」

use super::描画対象資源;
use crate::vulkan::descriptor::描画対象ディスクリプタ参照;
use crate::vulkan::visible_id::可視ID列バッファ;

impl 描画対象資源 {
    pub(in crate::renderer::scene_draw_resources) fn 材質スロット数(&self) -> usize {
        self.スロット別材質.件数()
    }

    /// そのスロット番号の材質がこの対象の中で何番目かを返す。持たなければ`None`。
    pub(in crate::renderer::scene_draw_resources) fn 材質スロット番号で添字を引く(&self, スロット番号: u32) -> Option<usize> {
        self.スロット別材質.スロット番号で添字を引く(スロット番号)
    }

    /// 材質スロット1つぶんのディスクリプタセットへ結ぶ資源の参照。単一個体の可視ID列だけは束が共有するため、束から借りて受け取る。
    /// 個体変換はスロットによらず対象に1本であり、どのスロットのセットも同じバッファを結ぶ。
    pub(in crate::renderer::scene_draw_resources) fn スロットのディスクリプタ参照<'a>(
        &'a self,
        スロット添字: usize,
        束の単一個体列: &可視ID列バッファ,
    ) -> Option<描画対象ディスクリプタ参照<'a>> {
        let 資源 = self.スロット別材質.添字で参照する(スロット添字)?;
        Some(描画対象ディスクリプタ参照 {
            テクスチャ: &資源.テクスチャ,
            シェーダー定数: &資源.シェーダー定数,
            個体変換: (self.個体変換.buffer, self.個体変換.範囲),
            可視id列: self.可視id列.参照(束の単一個体列),
        })
    }
}
