//! 描画対象の材質スロット番号を材質IDへ解決する操作と、ジオメトリのセットが結ぶ資源の参照。
//! 触れるのはスロット別材質ID・個体レコードの置き場・可視ID列の出どころの3つだけであり、段別ジオメトリと内容検査には触れない。
//! 材質スロット番号からの解決はこの1箇所だけが行う。
//!
//! 返すのが材質IDであってレコード添字でないのは、添字が資源表世代ごとに決まり直すからである。フレームの描画準備が
//! その時点で束縛する世代に対してこのIDを解決し、得た添字だけを描画定数へ載せる
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「材質レコードとテクスチャ台帳」)。

use super::描画対象資源;
use crate::vulkan::descriptor::ジオメトリセット参照;
use crate::vulkan::material_table::大域材質ID;
use crate::vulkan::visible_id::可視ID列バッファ;

impl 描画対象資源 {
    /// そのスロット番号の材質のIDを返す。持たなければ`None`。
    pub(in crate::renderer::scene_draw_resources) fn 材質スロット番号で解決する(
        &self, スロット番号: u32
    ) -> Option<大域材質ID> {
        self.スロット別材質id.スロット番号で引く(スロット番号)
    }

    /// ジオメトリのセットへ結ぶ資源の参照。材質スロットによらず対象に1組である。
    /// 単一個体の可視ID列だけは束が共有するため、束から借りて受け取る。
    pub(in crate::renderer::scene_draw_resources) fn ジオメトリセット参照を作る(
        &self,
        束の単一個体列: &可視ID列バッファ,
    ) -> ジオメトリセット参照 {
        ジオメトリセット参照 {
            個体レコード: self.個体変換.参照(),
            可視id列: self.可視id列.参照(束の単一個体列),
        }
    }
}
