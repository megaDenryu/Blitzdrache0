//! 描画対象の材質スロット番号を、その束の中での材質の位置と、ディスクリプタセットが結ぶ資源の参照へ解決する操作。
//! 触れるのはスロット別材質資源・材質レコードバッファ・個体変換バッファ・可視ID列の出どころの4つだけであり、
//! 段別ジオメトリと内容検査には触れない。材質スロット番号からの解決はこの1箇所だけが行う。
//!
//! 不変条件: スロットの並びは材質のセットの並びとも材質レコード列の並びとも同じである。束の生成が`材質スロット数`の
//! 範囲を順に引いて参照の列を作り、描画発行が`材質スロット番号で解決する`で得た参照で同じ並びのセットとレコードを選ぶため、
//! 3つがずれると別の材質を束ねたまま描画が成立する。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「束縛バックエンドの移行境界」

use super::描画対象資源;
use crate::renderer::scene_draw_resources::bundle_material_reference::束内材質参照;
use crate::vulkan::descriptor::{ジオメトリセット参照, 材質セット参照};
use crate::vulkan::visible_id::可視ID列バッファ;

impl 描画対象資源 {
    pub(in crate::renderer::scene_draw_resources) fn 材質スロット数(&self) -> usize {
        self.スロット別材質.件数()
    }

    /// そのスロット番号の材質がこの対象の中で何番目かを返す。持たなければ`None`。
    pub(in crate::renderer::scene_draw_resources) fn 材質スロット番号で解決する(
        &self, スロット番号: u32
    ) -> Option<束内材質参照> {
        self.スロット別材質.スロット番号で添字を引く(スロット番号).map(束内材質参照::生成する)
    }

    /// ジオメトリのセットへ結ぶ資源の参照。材質スロットによらず対象に1組である。
    /// 単一個体の可視ID列だけは束が共有するため、束から借りて受け取る。
    pub(in crate::renderer::scene_draw_resources) fn ジオメトリセット参照を作る(
        &self,
        束の単一個体列: &可視ID列バッファ,
    ) -> ジオメトリセット参照 {
        ジオメトリセット参照 {
            個体レコード: (self.レコード列.個体変換.buffer, self.レコード列.個体変換.範囲),
            可視id列: self.可視id列.参照(束の単一個体列),
        }
    }

    /// 材質スロット1つぶんの材質のセットへ結ぶ資源の参照。材質レコードはスロットによらず対象に1本であり、
    /// どのスロットのセットも同じバッファを結ぶ。
    pub(in crate::renderer::scene_draw_resources) fn スロットの材質セット参照(
        &self,
        スロット添字: usize,
    ) -> Option<材質セット参照<'_>> {
        let 資源 = self.スロット別材質.添字で参照する(スロット添字)?;
        Some(材質セット参照 {
            テクスチャ: &資源.テクスチャ,
            材質レコード: (self.レコード列.材質レコード.buffer, self.レコード列.材質レコード.範囲),
        })
    }
}
