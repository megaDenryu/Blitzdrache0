//! 個体ごとの球を1つの球へまとめる工程。受け取るのは個体1体ぶんの変換と原型の半径、
//! 返すのは全部を覆う1つの中心と半径である。呼び出し元は中身を知らずに呼べる。
//!
//! 保守的な側へ外すことがこの工程の契約である。覆い切れない球を返すと、面ごとの絞りが遮蔽物を落とし、
//! 影がその場所だけ抜ける。

use blitz_math::{ローカル, ワールド, 変換};

/// 個体1体ぶんの球。半径は3本の列の長さの最大で伸ばす。回転で向きが変わっても球は変わらないため、
/// 最大の倍率で伸ばせば保守的である。
pub(super) fn 個体の球を求める(変換: 変換<ローカル, ワールド>, 原型の半径: f32) -> ([f32; 3], f32) {
    let 列優先 = 変換.gpu境界用列優先配列();
    let 倍率 = (0..3)
        .map(|列| 長さ([列優先[列][0], 列優先[列][1], 列優先[列][2]]))
        .fold(0.0_f32, f32::max);
    ([列優先[3][0], 列優先[3][1], 列優先[3][2]], 原型の半径 * 倍率)
}

/// 個体ごとの球をすべて覆う1つの球。中心は中心の軸平行な包囲領域の真ん中に置く。
/// 個体を1体も持たない対象は原点の半径0の球になる(そのとき描く三角形も1つも無い)。
pub(super) fn 個体の球をまとめる(個体の球一覧: &[([f32; 3], f32)]) -> ([f32; 3], f32) {
    let Some((先頭の中心, _)) = 個体の球一覧.first() else {
        return ([0.0, 0.0, 0.0], 0.0);
    };
    let mut 最小 = *先頭の中心;
    let mut 最大 = *先頭の中心;
    for (中心, _) in 個体の球一覧 {
        for 軸 in 0..3 {
            最小[軸] = 最小[軸].min(中心[軸]);
            最大[軸] = 最大[軸].max(中心[軸]);
        }
    }
    let 中心 = [(最小[0] + 最大[0]) * 0.5, (最小[1] + 最大[1]) * 0.5, (最小[2] + 最大[2]) * 0.5];
    let 半径 = 個体の球一覧
        .iter()
        .map(|(個体の中心, 個体の半径)| 長さ(差(*個体の中心, 中心)) + 個体の半径)
        .fold(0.0_f32, f32::max);
    (中心, 半径)
}

pub(super) fn 長さ(成分: [f32; 3]) -> f32 {
    (成分[0] * 成分[0] + 成分[1] * 成分[1] + 成分[2] * 成分[2]).sqrt()
}

fn 差(甲: [f32; 3], 乙: [f32; 3]) -> [f32; 3] {
    [甲[0] - 乙[0], 甲[1] - 乙[1], 甲[2] - 乙[2]]
}
