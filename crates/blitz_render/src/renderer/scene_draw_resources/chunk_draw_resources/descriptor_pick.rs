//! 描画対象1つぶんの、ジオメトリのセットが決まっている状態。担当するのは、束が持つプールと描画対象添字と
//! フレームスロット添字の3つを組にして運ぶことである。
//!
//! 3つを別々に持ち回すと、描画発行を積む側が束と対象の対応を組み立て直すことになる。材質のセットはここに現れない。
//! 資源表世代が1つだけ持ち、パスの先頭で束縛済みだからである
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「束縛頻度による4セット」)。

use ash::vk;

use crate::vulkan::descriptor::描画対象ディスクリプタプール;
use crate::vulkan::sync::フレームスロット添字;

#[derive(Clone, Copy)]
pub(in crate::renderer::scene_draw_resources) struct 対象のディスクリプタ選択<'a> {
    プール: &'a 描画対象ディスクリプタプール,
    描画対象添字: usize,
    フレーム添字: フレームスロット添字,
}

impl<'a> 対象のディスクリプタ選択<'a> {
    pub(super) fn 生成する(
        プール: &'a 描画対象ディスクリプタプール, 描画対象添字: usize, フレーム添字: フレームスロット添字
    ) -> Self {
        Self {
            プール,
            描画対象添字,
            フレーム添字,
        }
    }

    /// この対象のそのフレームのジオメトリのセット(set1)。材質スロットによらず1つである。
    pub(in crate::renderer::scene_draw_resources) fn ジオメトリ(self) -> vk::DescriptorSet {
        self.プール.ジオメトリセット(self.描画対象添字, self.フレーム添字)
    }
}
