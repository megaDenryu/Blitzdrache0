//! シーン描画発行の整列の検査。材質の交互列が材質ごとにまとまること、その整列で材質切替だけが減って描画の数が変わらないこと、
//! 鍵が同じ発行が積んだ順を保つこと、入力の並びが違っても同じ集合からは同じ並びが出ることを見る。
//!
//! 検査が`ジオメトリ入力`そのものでなく整列鍵の上で行われるのは、並べ替えの規則が鍵の全順序だけで決まるためである。

#![allow(clippy::unwrap_used)]

use ash::vk;

use super::{シーン発行の整列鍵, 整列する};
use crate::visible_instance_selection::可視パス;
use crate::vulkan::frame::{記録側の計数, 記録側切替計数};
use crate::vulkan::material_table::大域材質ID;
use crate::vulkan::material_variant::材質変種キー;
use crate::vulkan::pipeline_ledger::{パイプラインキー, 描画先の一意化, 照明問い合わせ契約};

/// 検査用の発行。整列鍵と、積んだ順を見分けるための通し番号を持つ。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct 検査用発行 {
    材質番号: u64,
    通し番号: usize,
}

fn シーンのキー() -> パイプラインキー {
    パイプラインキー::シーン {
        描画先: 描画先の一意化::色と深度へ描く(vk::Format::R8G8B8A8_UNORM, vk::Format::D32_SFLOAT, vk::SampleCountFlags::TYPE_1),
        材質変種: 材質変種キー::標準金属粗さPBRの不透明両面,
        照明問い合わせ: 照明問い合わせ契約::直接光と多段影,
    }
}

fn 鍵(発行: &検査用発行) -> シーン発行の整列鍵 {
    シーン発行の整列鍵::生成する(シーンのキー(), 大域材質ID::生成する(発行.材質番号))
}

fn 積む(材質番号一覧: &[u64]) -> Vec<検査用発行> {
    材質番号一覧
        .iter()
        .enumerate()
        .map(|(通し番号, 材質番号)| 検査用発行 {
            材質番号: *材質番号,
            通し番号,
        })
        .collect()
}

fn 材質番号の並び(一覧: &[検査用発行]) -> Vec<u64> {
    一覧.iter().map(|発行| 発行.材質番号).collect()
}

#[test]
fn 材質の交互列は材質ごとにまとまる() {
    let mut 一覧 = 積む(&[1, 2, 1, 2]);
    整列する(&mut 一覧, 鍵);
    assert_eq!(材質番号の並び(&一覧), vec![1, 1, 2, 2]);
    assert_eq!(一覧.len(), 4, "整列で発行の件数が変わった");
}

/// 並びをそのまま記録したときの計数。記録の局面と同じ順で材質を見せて描くため、実機の記録が数える値と同じ規則で出る。
fn 記録したとして数える(一覧: &[検査用発行]) -> 記録側の計数 {
    let 計器 = 記録側切替計数::default();
    for 発行 in 一覧 {
        計器.材質を見る(可視パス::シーン, 大域材質ID::生成する(発行.材質番号));
        計器.描画を数える(可視パス::シーン);
    }
    計器.パスの計数(可視パス::シーン)
}

#[test]
fn 材質の交互列を整列すると材質切替だけが減る() {
    let mut 一覧 = 積む(&[1, 2, 1, 2]);
    let 整列前 = 記録したとして数える(&一覧);
    整列する(&mut 一覧, 鍵);
    let 整列後 = 記録したとして数える(&一覧);
    assert_eq!(整列前.材質切替(), 4, "交互列の材質切替が4回でない");
    assert_eq!(整列後.材質切替(), 2, "整列後の材質切替が材質の数と同じ2回でない");
    assert_eq!(整列前.描画数(), 整列後.描画数(), "整列で描画の数が変わった");
    assert_eq!(整列後.描画数(), 4, "描画の数が発行の件数と違う");
}

#[test]
fn 同じ材質の発行は積んだ順を保つ() {
    let mut 一覧 = 積む(&[2, 1, 2, 1]);
    整列する(&mut 一覧, 鍵);
    let 通し番号 = 一覧.iter().map(|発行| 発行.通し番号).collect::<Vec<_>>();
    assert_eq!(通し番号, vec![1, 3, 0, 2]);
}

#[test]
fn 走査順が違っても同じ集合からは同じ並びが出る() {
    let mut 走査順1 = 積む(&[1, 2]);
    let mut 走査順2 = 積む(&[2, 1]);
    整列する(&mut 走査順1, 鍵);
    整列する(&mut 走査順2, 鍵);
    assert_eq!(材質番号の並び(&走査順1), 材質番号の並び(&走査順2));
}
