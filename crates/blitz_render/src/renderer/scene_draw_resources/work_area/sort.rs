//! 積み終えたシーンパスの描画発行を、束縛の切替が少なくなる並びへ整列する工程。受け取るのは1フレームぶんの発行の並びと
//! 発行から整列鍵を取る関数、返すのは同じ要素を全順序で並べ替えた同じ並びである。
//!
//! 全順序は「材質変種キー→大域材質ID→積んだ順」である。先頭に変種キーを置くのはパイプラインの切替が最も高くつくためであり、
//! 次に材質IDを置くのは同じ材質を連続させて材質切替を減らすためである。最後の「積んだ順」は安定ソートが保つため鍵に持たない。
//! 注意: 世代内の材質レコード添字で並べてはならない。添字は資源表世代を作り直すたびに並び直るため、材質の中身が同じでも
//! アセットのリロードの前後で描画順が変わる(参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段6)。
//! 整列するのは不透明なシーンの描画項目だけであり、影の発行も布も粒子もこの並べ替えの対象にしない。

#[cfg(test)]
mod order_tests;

use super::super::シーン描画資源;
use crate::vulkan::material_table::大域材質ID;
use crate::vulkan::material_variant::材質変種キー;

/// 1つのシーン描画発行を並べる鍵。全順序であることは導出した`Ord`が保つ。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub(in crate::renderer) struct シーン発行の整列鍵 {
    変種キー: 材質変種キー,
    材質id: 大域材質ID,
}

impl シーン発行の整列鍵 {
    pub(in crate::renderer) const fn 生成する(変種キー: 材質変種キー, 材質id: 大域材質ID) -> Self {
        Self { 変種キー, 材質id }
    }
}

/// 安定ソートを使うのは、鍵が同じ発行の並びを積んだ順のままにするためである。積んだ順は走査の順であり、
/// 同じ深度の面がどちらの色になるかをこの順が決める。不安定ソートにすると同じ入力から2つの絵が出うる。
fn 整列する<要素>(一覧: &mut [要素], 鍵: impl Fn(&要素) -> シーン発行の整列鍵) {
    一覧.sort_by_key(鍵);
}

impl シーン描画資源 {
    /// 前提: そのフレームのシーン発行を積み終えてから1回だけ呼ぶ。積む途中で呼ぶと、後から積んだ発行が整列の外に残る。
    pub(super) fn シーン発行を整列する(&mut self) {
        整列する(&mut self.ジオメトリ入力作業領域, |入力| {
            シーン発行の整列鍵::生成する(入力.材質変種キー, 入力.大域材質id)
        });
    }
}
