//! 描画対象1つぶんの、点光源の影の描画発行を積む工程。受け取るのは描画対象の材料と基準原点のカメラ相対位置、
//! 積むのは束の詳細段のプリミティブごとの発行である。
//!
//! 距離区分のシャドウと違い、パスごとにも段ごとにも分けない。可視ID列を読まないため描くのは常に全個体であり、
//! 段は束の詳細段1つで足りる。面ごとの絞りはコマンド記録の地点が球の判定で行う
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断n」)。
//!
//! 影を落とす灯が1件も無いフレームでは1件も積まない。積んでも読む側のパスが1本も無く、走査だけが残るためである。

use blitz_math::{カメラ相対位置, メートル, ワールド, 位置};

use super::object_entry::描画対象の材料;
use crate::error::レンダラーエラー;
use crate::vulkan::frame::点光源の影の描画発行;
use crate::vulkan::relative_anchor::カメラ相対の基準原点;

pub(super) fn 積む(
    材料: &描画対象の材料<'_>,
    積み先: &mut Vec<点光源の影の描画発行>,
    基準原点のカメラ相対位置: カメラ相対位置,
    相対の基準原点: カメラ相対の基準原点,
) -> Result<(), レンダラーエラー> {
    if 材料.入力.点光源の影の計画.灯の件数() == 0 {
        return Ok(());
    }
    let 個体数 = 材料.資源.個体数();
    if 個体数 == 0 {
        return Ok(());
    }
    let 有効段番号 = 材料.資源.有効な段番号(材料.段.添字());
    let ジオメトリ = 材料.資源.段を番号で選ぶ(有効段番号);
    let 頂点バッファ = 材料.頂点バッファ差し替え先().unwrap_or(ジオメトリ.頂点バッファ);
    let 絞りの球 = 絞りの球を作る(材料, 基準原点のカメラ相対位置);
    for 発行 in 材料.プリミティブ発行.iter().filter(|発行| 発行.詳細段番号() == 有効段番号) {
        積み先.push(点光源の影の描画発行 {
            頂点バッファ,
            インデックスバッファ: ジオメトリ.インデックスバッファ,
            先頭インデックス: 発行.インデックス開始(),
            インデックス数: 発行.インデックス数(),
            頂点基準: 発行.頂点基準(),
            個体数,
            ジオメトリセット: 材料.ディスクリプタ選択.ジオメトリ(),
            相対の基準原点,
            絞りの球,
        });
    }
    Ok(())
}

/// 描画対象の境界球をカメラ相対の位置へ移す。球を持たない対象(動く個体を宣言した対象)は値なしで返し、
/// 記録の側がどの面でも候補として通す。
fn 絞りの球を作る(
    材料: &描画対象の材料<'_>, 基準原点のカメラ相対位置: カメラ相対位置
) -> Option<(位置<ワールド>, メートル)> {
    材料.資源.境界球().中心と半径().map(|(中心, 半径)| {
        let 位置 = 位置::生成する(
            メートル::生成する(基準原点のカメラ相対位置.x().値() + 中心[0]),
            メートル::生成する(基準原点のカメラ相対位置.y().値() + 中心[1]),
            メートル::生成する(基準原点のカメラ相対位置.z().値() + 中心[2]),
        );
        (位置, 半径)
    })
}
