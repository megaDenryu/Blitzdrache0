//! 毎フレームの描画発行を数える集計。段ごとの個体数を2本の使い回す列で持ち、フレームの終わりに内訳へ写す。
//! 集計を型として分けるのは、作業領域の充填が「入力を積む」ことと「積んだものを数える」ことの2つを同時に行うためであり、
//! 数える側の状態をここへ閉じると充填側は積むことだけを見ればよくなる。
//! 列を使い回すのは、段数ぶんのヒープ確保を毎フレーム起こさないためである。

use crate::renderer::draw_issue_breakdown::{パス別描画発行, 描画発行内訳, 段別個体数};

#[derive(Default)]
pub(in crate::renderer) struct 描画計数集計 {
    全個体数: u64,
    シーン可視数: u64,
    シャドウ可視数: u64,
    シーン段別個体数: Vec<u64>,
    シャドウ段別個体数: Vec<u64>,
}

impl 描画計数集計 {
    pub(super) fn 集計を始める(&mut self) {
        self.全個体数 = 0;
        self.シーン可視数 = 0;
        self.シャドウ可視数 = 0;
        self.シーン段別個体数.clear();
        self.シャドウ段別個体数.clear();
    }

    /// 描画対象1つが持つ個体の数。両パスの可視判定の候補数に当たり、積んだ発行のインスタンス数とは別の出どころである。
    pub(super) fn 対象の個体数を加える(&mut self, 個体数: u64) {
        self.全個体数 += 個体数;
    }

    /// 可視判定がそれぞれのパスへ可視と判じた数。積んだ発行のインスタンス数と一致することが整合の証拠になる。
    /// 2つを1回の呼び出しで受けるのは、どちらも同じ段の同じ選択から出る組であり、片方だけの計上を作らないためである。
    pub(super) fn パス別可視数を加える(&mut self, シーン可視数: u64, シャドウ可視数: u64) {
        self.シーン可視数 += シーン可視数;
        self.シャドウ可視数 += シャドウ可視数;
    }

    pub(super) fn 段へ加える(&mut self, 段番号: usize, シーン個体数: u64, シャドウ個体数: u64) {
        加算する(&mut self.シーン段別個体数, 段番号, シーン個体数);
        加算する(&mut self.シャドウ段別個体数, 段番号, シャドウ個体数);
    }

    /// 発行数だけは積んだ入力の件数そのものであるため、充填側から受け取る。
    pub(in crate::renderer) fn 内訳を作る(&self, シーン発行数: usize, シャドウ発行数: usize) -> 描画発行内訳 {
        描画発行内訳::生成する(
            パス別描画発行::生成する(
                シーン発行数,
                self.全個体数,
                self.シーン可視数,
                段別個体数::一覧から生成する(self.シーン段別個体数.clone()),
            ),
            パス別描画発行::生成する(
                シャドウ発行数,
                self.全個体数,
                self.シャドウ可視数,
                段別個体数::一覧から生成する(self.シャドウ段別個体数.clone()),
            ),
        )
    }
}

/// 段番号の位置まで0で伸ばしてから足す。段番号は原型の段数までしか来ないため、伸長は起動直後の数フレームで止まる。
fn 加算する(一覧: &mut Vec<u64>, 段番号: usize, 個体数: u64) {
    if 一覧.len() <= 段番号 {
        一覧.resize(段番号 + 1, 0);
    }
    match 一覧.get_mut(段番号) {
        Some(値) => *値 += 個体数,
        None => panic!("段別個体数の列を段番号まで伸ばしたという不変条件に違反した: 段番号{段番号}"),
    }
}
