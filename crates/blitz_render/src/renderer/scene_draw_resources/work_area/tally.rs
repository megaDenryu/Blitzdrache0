//! 毎フレームの描画発行を数える集計。パスごとに可視数と段別個体数を持ち、フレームの終わりに内訳へ写す。
//! 集計を型として分けるのは、作業領域の充填が「入力を積む」ことと「積んだものを数える」ことの2つを同時に行うためであり、
//! 数える側の状態をここへ閉じると充填側は積むことだけを見ればよくなる。
//! 段別の列を使い回すのは、段数ぶんのヒープ確保を毎フレーム起こさないためである。

use crate::renderer::draw_issue_breakdown::{パス別描画発行, 描画発行内訳, 段別個体数};
use crate::visible_instance_selection::{可視ID列を読むパス数, 可視パス};
use crate::vulkan::frame::記録側の計数;

/// 1つのパスぶんの集計。触れるのは自分のパスの可視数と段別個体数だけである。
/// `投入インデックス数`は頂点処理量の代理変数である。
#[derive(Default)]
struct パス別集計 {
    可視数: u64,
    段別個体数: Vec<u64>,
    投入インデックス数: u64, // 積んだ発行のインデックス数とインスタンス数の積の総和
}

#[derive(Default)]
pub(in crate::renderer) struct 描画計数集計 {
    全個体数: u64,
    パス別: [パス別集計; 可視ID列を読むパス数],
}

impl 描画計数集計 {
    pub(super) fn 集計を始める(&mut self) {
        self.全個体数 = 0;
        for 集計 in &mut self.パス別 {
            集計.可視数 = 0;
            集計.段別個体数.clear();
            集計.投入インデックス数 = 0;
        }
    }

    /// 描画対象1つが持つ個体の数。どのパスでも同じ候補数に当たり、積んだ発行のインスタンス数とは別の出どころである。
    pub(super) fn 対象の個体数を加える(&mut self, 個体数: u64) {
        self.全個体数 += 個体数;
    }

    /// あるパスの段1つぶんの描画数。可視数と段別個体数の両方へ同じ値を足すのは、2つが同じ区間から出る組であり、
    /// 片方だけの計上を作らないためである。
    pub(super) fn パスの段へ加える(&mut self, パス: 可視パス, 段番号: usize, 描画数: u64) {
        let 集計 = &mut self.パス別[パス.添字()];
        集計.可視数 += 描画数;
        加算する(&mut 集計.段別個体数, 段番号, 描画数);
    }

    /// 1つの発行のインデックス数とインスタンス数の積。段でなくパスへ足すのは、この量を読むのが距離区分ごとの
    /// 費用の支配要因の判定であり、段への分解が要らないためである。段の分布は段別個体数が示す。
    pub(super) fn パスへ投入インデックス数を加える(&mut self, パス: 可視パス, インデックス数: u64) {
        self.パス別[パス.添字()].投入インデックス数 += インデックス数;
    }

    /// 発行数だけは積んだ入力の件数そのものであるため、パスから件数を引く関数を充填側から受け取る。
    /// 記録側の計数も同じ形で受け取る。数える主体が記録の局面であり、この集計は値を運ぶだけだからである。
    pub(in crate::renderer) fn 内訳を作る(
        &self,
        発行数を引く: impl Fn(可視パス) -> usize,
        記録側を引く: impl Fn(可視パス) -> 記録側の計数,
    ) -> 描画発行内訳 {
        let mut パス別 = std::array::from_fn(|_| パス別描画発行::空());
        for パス in 可視パス::全パス() {
            let 集計 = &self.パス別[パス.添字()];
            パス別[パス.添字()] = パス別描画発行::生成する(
                発行数を引く(パス),
                self.全個体数,
                集計.可視数,
                段別個体数::一覧から生成する(集計.段別個体数.clone()),
                集計.投入インデックス数,
                記録側を引く(パス),
            );
        }
        描画発行内訳::生成する(パス別)
    }
}

/// 段番号の位置まで0で伸ばしてから足す。段番号は原型の段数までしか来ないため、伸長は起動直後の数フレームで止まる。
/// 直前の伸長が保証する位置へ添字するため、ここで失敗することはない。
fn 加算する(一覧: &mut Vec<u64>, 段番号: usize, 個体数: u64) {
    if 一覧.len() <= 段番号 {
        一覧.resize(段番号 + 1, 0);
    }
    一覧[段番号] += 個体数;
}
