//! 描画対象1つぶんの描画入力を組み立てる工程。受け取るのは対象の資源とそのフレームの外部条件、返すのは
//! シーンパスのジオメトリ入力(可視個体が居なければ無し)とシャドウ描画入力の組である。
//! 可視ID列のGPUへの書き込みもここで行う。書き込む内容と描くインスタンス数は同じ判定から出るため、離すと食い違いうる。
//! 注意: シャドウ描画入力のインスタンス数は常に全個体である。カメラ視錐台で絞った可視集合をシャドウへ流用してはならない
//! (参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」)。

use ash::vk;

use super::作業領域更新入力;
use crate::draw_bundle_id::描画束ID;
use crate::error::レンダラーエラー;
use crate::renderer::scene_draw_resources::render_object_resources::描画対象資源;
use crate::terrain_detail::地形詳細段;
use crate::vulkan::frame::{シャドウ描画入力, ジオメトリ入力};
use crate::vulkan::relative_anchor::カメラ相対アンカー;

pub(super) struct 描画対象の材料<'a> {
    pub(super) 入力: &'a 作業領域更新入力<'a>,
    pub(super) 束id: 描画束ID,
    pub(super) 対象添字: usize,
    pub(super) 資源: &'a 描画対象資源,
    pub(super) ディスクリプタセット: vk::DescriptorSet,
    pub(super) 段: 地形詳細段,
    /// スキニングはシーンの先頭対象だけへ適用する(判断44の既存契約)。可視判定で先頭が描かれなくなっても、
    /// 差し替え先の判断は走査順の先頭で決まる。
    pub(super) 先頭対象か: bool,
}

pub(super) struct 描画対象の入力 {
    pub(super) ジオメトリ: Option<ジオメトリ入力>,
    pub(super) シャドウ: シャドウ描画入力,
    pub(super) シーン可視数: u32,
}

pub(super) fn 組み立てる(材料: &描画対象の材料<'_>) -> Result<描画対象の入力, レンダラーエラー> {
    let 入力 = 材料.入力;
    let ジオメトリ = 材料.資源.段を選ぶ(材料.段);
    let 頂点バッファ = if 材料.先頭対象か {
        入力.スキン済み頂点バッファ.unwrap_or(ジオメトリ.頂点バッファ)
    } else {
        ジオメトリ.頂点バッファ
    };
    let 相対アンカー = カメラ相対アンカー::相対位置から生成する(材料.資源.大域アンカー.カメラ相対へ変換する(入力.カメラ大域原点)?);
    let シーン可視数 = 可視数を決めて書き込む(材料)?;
    let シーン入力 = (シーン可視数 > 0).then_some(ジオメトリ入力 {
        頂点バッファ,
        インデックスバッファ: ジオメトリ.インデックスバッファ,
        インデックス数: ジオメトリ.インデックス数,
        インスタンス数: シーン可視数,
        layout: 入力.シーンlayout,
        ディスクリプタセット: 材料.ディスクリプタセット,
        相対アンカー,
    });
    Ok(描画対象の入力 {
        ジオメトリ: シーン入力,
        シャドウ: シャドウ描画入力 {
            pipeline: 入力.シャドウpipeline,
            layout: 入力.シャドウlayout,
            頂点バッファ,
            インデックスバッファ: ジオメトリ.インデックスバッファ,
            インデックス数: ジオメトリ.インデックス数,
            インスタンス数: 材料.資源.個体数(),
            ディスクリプタセット: 材料.ディスクリプタセット,
            相対アンカー,
        },
        シーン可視数,
    })
}

/// 可視個体選択があればその添字列をこのフレームのバッファへ書き、可視数を返す。選択が無い対象は
/// 生成時に書いた恒等の列をそのまま読むため、書き込まずに全個体数を返す。
fn 可視数を決めて書き込む(材料: &描画対象の材料<'_>) -> Result<u32, レンダラーエラー> {
    let Some(可視id列) = 材料.入力.可視個体選択一覧.引く(材料.束id, 材料.対象添字) else {
        return Ok(材料.資源.個体数());
    };
    材料.資源.可視id列を書き込む(材料.入力.device, 材料.入力.フレーム添字, 可視id列)?;
    u32::try_from(可視id列.len()).map_err(|_| レンダラーエラー::個体数過大(可視id列.len()))
}
