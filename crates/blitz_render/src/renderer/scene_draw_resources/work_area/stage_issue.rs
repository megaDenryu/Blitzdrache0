//! LOD段1つぶんの描画発行を積む工程。受け取るのは描画対象の材料と段番号と段のパス別区間、積むのは
//! パスごとの描画入力である。そのパスの描画数が0の段は、そのパスの発行を作らない。
//! 個体を1体も持たない段は発行そのものを作らない。描画発行が群×非空段×パスごとに1回であることの実装がここである。
//! シャドウの発行は距離区分ごとに別の列へ積む。距離区分別のカリングでは距離区分ごとに描く個体が違うため、1本の列を4距離区分で共有できない
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」)。

use super::object_entry::描画対象の材料;
use super::描画発行受け皿;
use crate::visible_instance_selection::{可視パス, 段別描画範囲};
use crate::vulkan::frame::{シャドウ描画入力, ジオメトリ入力};
use crate::vulkan::relative_anchor::カメラ相対アンカー;

pub(super) fn 積む(
    材料: &描画対象の材料<'_>,
    受け皿: &mut 描画発行受け皿<'_>,
    段番号: usize,
    範囲: 段別描画範囲,
    相対アンカー: カメラ相対アンカー,
) {
    if 範囲.個体数() == 0 {
        return;
    }
    let ジオメトリ = 材料.資源.段を番号で選ぶ(段番号);
    let 頂点バッファ = 材料.頂点バッファ差し替え先().unwrap_or(ジオメトリ.頂点バッファ);
    for パス in 可視パス::全パス() {
        let 区間 = 範囲.パス(パス);
        受け皿.集計.パスの段へ加える(パス, 段番号, u64::from(区間.描画数()));
        if 区間.描画数() == 0 {
            continue;
        }
        match パス {
            可視パス::シーン => 受け皿.ジオメトリ.push(ジオメトリ入力 {
                頂点バッファ,
                インデックスバッファ: ジオメトリ.インデックスバッファ,
                インデックス数: ジオメトリ.インデックス数,
                インスタンス数: 区間.描画数(),
                先頭インスタンス: 区間.開始(),
                layout: 材料.入力.シーンlayout,
                ディスクリプタセット: 材料.ディスクリプタセット,
                相対アンカー,
            }),
            可視パス::影の距離区分(番号) => 受け皿.距離区分別のシャドウ[番号.添字()].push(シャドウ描画入力 {
                pipeline: 材料.入力.シャドウpipeline,
                layout: 材料.入力.シャドウlayout,
                頂点バッファ,
                インデックスバッファ: ジオメトリ.インデックスバッファ,
                インデックス数: ジオメトリ.インデックス数,
                インスタンス数: 区間.描画数(),
                先頭インスタンス: 区間.開始(),
                ディスクリプタセット: 材料.ディスクリプタセット,
                相対アンカー,
            }),
        }
    }
}
