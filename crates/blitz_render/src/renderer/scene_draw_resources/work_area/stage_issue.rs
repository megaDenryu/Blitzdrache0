//! LOD段1つぶんの描画発行を積む工程。受け取るのは描画対象の材料と段番号と段の範囲、積むのは
//! パスごとの描画入力である。そのパスの描画数が0の段は、そのパスの発行を作らない。
//! 個体を1体も持たない段は発行そのものを作らない。描画発行が群×非空段ごとに1回であることの実装がここである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「描画発行」

use super::object_entry::描画対象の材料;
use super::描画発行受け皿;
use crate::visible_instance_selection::段別描画範囲;
use crate::vulkan::frame::{シャドウ描画入力, ジオメトリ入力};
use crate::vulkan::relative_anchor::カメラ相対アンカー;

pub(super) fn 積む(
    材料: &描画対象の材料<'_>,
    受け皿: &mut 描画発行受け皿<'_>,
    段番号: usize,
    範囲: 段別描画範囲,
    相対アンカー: カメラ相対アンカー,
) {
    if 範囲.個体数() == 0 {
        return;
    }
    let ジオメトリ = 材料.資源.段を番号で選ぶ(段番号);
    let 頂点バッファ = 材料.頂点バッファ差し替え先().unwrap_or(ジオメトリ.頂点バッファ);
    let (シーン, シャドウ) = (範囲.シーン(), 範囲.シャドウ());
    if シーン.描画数() > 0 {
        受け皿.ジオメトリ.push(ジオメトリ入力 {
            頂点バッファ,
            インデックスバッファ: ジオメトリ.インデックスバッファ,
            インデックス数: ジオメトリ.インデックス数,
            インスタンス数: シーン.描画数(),
            先頭インスタンス: シーン.開始(),
            layout: 材料.入力.シーンlayout,
            ディスクリプタセット: 材料.ディスクリプタセット,
            相対アンカー,
        });
    }
    if シャドウ.描画数() > 0 {
        受け皿.シャドウ.push(シャドウ描画入力 {
            pipeline: 材料.入力.シャドウpipeline,
            layout: 材料.入力.シャドウlayout,
            頂点バッファ,
            インデックスバッファ: ジオメトリ.インデックスバッファ,
            インデックス数: ジオメトリ.インデックス数,
            インスタンス数: シャドウ.描画数(),
            先頭インスタンス: シャドウ.開始(),
            ディスクリプタセット: 材料.ディスクリプタセット,
            相対アンカー,
        });
    }
    受け皿.集計.段へ加える(段番号, u64::from(シーン.描画数()), u64::from(シャドウ.描画数()));
}
