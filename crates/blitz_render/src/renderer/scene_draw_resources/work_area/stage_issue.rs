//! LOD段1つぶんの描画発行を積む工程。受け取るのは描画対象の材料と段番号と段のパス別区間、積むのは
//! パスごと・その段のプリミティブごとの描画入力である。そのパスの描画数が0の段は、そのパスの発行を作らない。
//! 個体を1体も持たない段は発行そのものを作らない。描画発行が群×非空段×パス×プリミティブごとに1回であることの実装がここである。
//!
//! 同じ段のプリミティブは同じ可視個体区間を共有する。可視選別を個体・原型・詳細段について1回だけ行う契約がこれであり、
//! 計数へ加えるのも段ごとに1回だけである。プリミティブの数で増えるのは積んだ入力の件数だけであり、可視数と個体数は増えない
//! (参照: `_doc/設計/マルチマテリアルと材質境界.md`「可視ID列の契約」)。
//! シャドウの発行は距離区分ごとに別の列へ積む。距離区分別の可視個体の選別では距離区分ごとに描く個体が違うため、1本の列を4距離区分で共有できない
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」)。
//! シーンの発行が深度プリパスのパイプラインも一緒に持つのは、両者が同じ材質変種から決まる組であり、離すと片方だけ別の変種の実体になりうるためである。
//! 材質スロット番号から資源表世代の中の位置と材質変種キーへの解決は`material_resolve`が持つ。

mod material_resolve;

use material_resolve::材質スロットを解決する;

use super::object_entry::描画対象の材料;
use super::描画発行受け皿;
use crate::error::レンダラーエラー;
use crate::visible_instance_selection::{可視パス, 段別描画範囲};
use crate::vulkan::frame::{シャドウ描画入力, ジオメトリ入力};
use crate::vulkan::relative_anchor::カメラ相対の基準原点;
use crate::vulkan::scene_draw_constants::シーン描画定数;

pub(super) fn 積む(
    材料: &描画対象の材料<'_>,
    受け皿: &mut 描画発行受け皿<'_>,
    段番号: usize,
    範囲: 段別描画範囲,
    相対の基準原点: カメラ相対の基準原点,
) -> Result<(), レンダラーエラー> {
    if 範囲.個体数() == 0 {
        return Ok(());
    }
    let 有効段番号 = 材料.資源.有効な段番号(段番号);
    let ジオメトリ = 材料.資源.段を番号で選ぶ(有効段番号);
    let 頂点バッファ = 材料.頂点バッファ差し替え先().unwrap_or(ジオメトリ.頂点バッファ());
    for パス in 材料.入力.影のキャスター.積むパス一覧() {
        if !材料.影方針.パスを描くか(パス) {
            continue;
        }
        let 区間 = 範囲.パス(パス);
        受け皿.集計.パスの段へ加える(パス, 段番号, u64::from(区間.描画数()));
        if 区間.描画数() == 0 {
            continue;
        }
        let 台帳 = 材料.入力.パイプライン台帳;
        let シャドウのキー = 台帳.シャドウのキー();
        let シャドウpipeline = 台帳.引く(シャドウのキー)?;
        for 発行 in 材料.プリミティブ発行.iter().filter(|発行| 発行.詳細段番号() == 有効段番号) {
            受け皿
                .集計
                .パスへ投入インデックス数を加える(パス, u64::from(区間.描画数()) * u64::from(発行.インデックス数()));
            let (材質id, 解決) = 材質スロットを解決する(材料, *発行)?;
            let シーンのキー = 台帳.シーンのキー(解決.変種キー());
            match パス {
                可視パス::シーン => 受け皿.ジオメトリ.push(ジオメトリ入力 {
                    頂点バッファ,
                    インデックスバッファ: ジオメトリ.インデックスバッファ(),
                    先頭インデックス: 発行.インデックス開始(),
                    インデックス数: 発行.インデックス数(),
                    頂点基準: 発行.頂点基準(),
                    インスタンス数: 区間.描画数(),
                    先頭インスタンス: 区間.開始(),
                    pipeline: 台帳.引く(シーンのキー)?,
                    深度プリパスpipeline: 台帳.引く(台帳.深度プリパスのキー(解決.変種キー()))?,
                    パイプラインキー: シーンのキー,
                    layout: 台帳.シーンlayout(),
                    ジオメトリセット: 材料.ディスクリプタ選択.ジオメトリ(),
                    描画定数: シーン描画定数::生成する(相対の基準原点, 解決.レコード添字().添字()),
                    大域材質id: 材質id,
                }),
                可視パス::影の距離区分(番号) => 受け皿.距離区分別のシャドウ[番号.添字()].push(シャドウ描画入力 {
                    pipeline: シャドウpipeline,
                    layout: 台帳.シャドウlayout(),
                    頂点バッファ,
                    インデックスバッファ: ジオメトリ.インデックスバッファ(),
                    先頭インデックス: 発行.インデックス開始(),
                    インデックス数: 発行.インデックス数(),
                    頂点基準: 発行.頂点基準(),
                    インスタンス数: 区間.描画数(),
                    先頭インスタンス: 区間.開始(),
                    ジオメトリセット: 材料.ディスクリプタ選択.ジオメトリ(),
                    相対の基準原点,
                }),
            }
        }
    }
    Ok(())
}
