//! LOD段1つぶんの描画発行を積む工程。受け取るのは描画対象の材料と段番号と段のパス別区間、積むのは
//! パスごと・その段のプリミティブごとの描画入力である。そのパスの描画数が0の段は、そのパスの発行を作らない。
//! 個体を1体も持たない段は発行そのものを作らない。描画発行が群×非空段×パス×プリミティブごとに1回であることの実装がここである。
//!
//! 同じ段のプリミティブは同じ可視個体区間を共有する。可視選別を個体・原型・詳細段について1回だけ行う契約がこれであり、
//! 計数へ加えるのも段ごとに1回だけである。プリミティブの数で増えるのは積んだ入力の件数だけであり、可視数と個体数は増えない
//! (参照: `_doc/設計/マルチマテリアルと材質境界.md`「可視ID列の契約」)。
//! シャドウの発行は距離区分ごとに別の列へ積む。距離区分別の可視個体の選別では距離区分ごとに描く個体が違うため、1本の列を4距離区分で共有できない
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」)。

use super::object_entry::描画対象の材料;
use super::描画発行受け皿;
use crate::error::{フレーム入力不一致エラー, レンダラーエラー};
use crate::frame_input::プリミティブ描画発行;
use crate::renderer::scene_draw_resources::bundle_material_reference::束内材質参照;
use crate::visible_instance_selection::{可視パス, 段別描画範囲};
use crate::vulkan::frame::{シャドウ描画入力, ジオメトリ入力};
use crate::vulkan::relative_anchor::カメラ相対の基準原点;
use crate::vulkan::scene_draw_constants::シーン描画定数;

pub(super) fn 積む(
    材料: &描画対象の材料<'_>,
    受け皿: &mut 描画発行受け皿<'_>,
    段番号: usize,
    範囲: 段別描画範囲,
    相対の基準原点: カメラ相対の基準原点,
) -> Result<(), レンダラーエラー> {
    if 範囲.個体数() == 0 {
        return Ok(());
    }
    let 有効段番号 = 材料.資源.有効な段番号(段番号);
    let ジオメトリ = 材料.資源.段を番号で選ぶ(有効段番号);
    let 頂点バッファ = 材料.頂点バッファ差し替え先().unwrap_or(ジオメトリ.頂点バッファ);
    for パス in 可視パス::全パス() {
        let 区間 = 範囲.パス(パス);
        受け皿.集計.パスの段へ加える(パス, 段番号, u64::from(区間.描画数()));
        if 区間.描画数() == 0 {
            continue;
        }
        for 発行 in 材料.プリミティブ発行.iter().filter(|発行| 発行.詳細段番号() == 有効段番号) {
            let 材質参照 = 材質スロットを解決する(材料, *発行)?;
            let セット = 材料.ディスクリプタ選択.スロット(材質参照);
            match パス {
                可視パス::シーン => 受け皿.ジオメトリ.push(ジオメトリ入力 {
                    頂点バッファ,
                    インデックスバッファ: ジオメトリ.インデックスバッファ,
                    先頭インデックス: 発行.インデックス開始(),
                    インデックス数: 発行.インデックス数(),
                    頂点基準: 発行.頂点基準(),
                    インスタンス数: 区間.描画数(),
                    先頭インスタンス: 区間.開始(),
                    layout: 材料.入力.シーンlayout,
                    ディスクリプタセット: セット,
                    描画定数: シーン描画定数::生成する(相対の基準原点, 材質参照.材質レコード添字()),
                }),
                可視パス::影の距離区分(番号) => 受け皿.距離区分別のシャドウ[番号.添字()].push(シャドウ描画入力 {
                    pipeline: 材料.入力.シャドウpipeline,
                    layout: 材料.入力.シャドウlayout,
                    頂点バッファ,
                    インデックスバッファ: ジオメトリ.インデックスバッファ,
                    先頭インデックス: 発行.インデックス開始(),
                    インデックス数: 発行.インデックス数(),
                    頂点基準: 発行.頂点基準(),
                    インスタンス数: 区間.描画数(),
                    先頭インスタンス: 区間.開始(),
                    ディスクリプタセット: セット,
                    相対の基準原点,
                }),
            }
        }
    }
    Ok(())
}

/// 発行が指す材質スロット番号を、この描画対象の中での材質の位置へ解決する。得た参照がディスクリプタセットの選択と
/// 描画定数の材質レコード添字の両方に使われるため、2つが別の材質を指すことがない。
/// 番号が資源に無いのは、レンダラーへ載せた材質集合と描画発行が別の原型から来ている状態であり、無言で他の材質を束ねずに失敗させる。
fn 材質スロットを解決する(
    材料: &描画対象の材料<'_>, 発行: プリミティブ描画発行
) -> Result<束内材質参照, レンダラーエラー> {
    材料.資源.材質スロット番号で解決する(発行.材質スロット番号()).ok_or_else(|| {
        フレーム入力不一致エラー::材質スロット未確保 {
            描画対象添字: 材料.対象添字,
            スロット番号: 発行.材質スロット番号(),
        }
        .into()
    })
}
