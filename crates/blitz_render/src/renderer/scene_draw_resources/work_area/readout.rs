//! 充填し終えた作業領域から、そのフレームの描画発行内訳と描画対象入力を読み出す局面。
//! 充填と分けるのは、呼ばれるタイミングが違うためである。充填はフレームの走査の中で1度だけ書き、読み出しは書き終えた後にだけ呼ばれ、何も書き換えない。
//! 前提: どちらも同じフレームで`作業領域を更新する`を済ませてから呼ぶ。中身が前フレームの残りだと、内訳も描画対象入力も1フレーム古い値になる。

use super::super::シーン描画資源;
use crate::renderer::draw_issue_breakdown::描画発行内訳;
use crate::visible_instance_selection::可視パス;
use crate::vulkan::frame::{共有セット束縛, 描画対象入力, 距離区分別のシャドウ入力};

impl シーン描画資源 {
    /// 直近のフレームで積んだ内訳。`作業領域を更新する`が最後に数えた値から作る。
    /// 発行数だけは積んだ入力の件数そのものであるため、パスごとの列の長さを`可視パス`で場合分けして集計へ渡す。
    /// 添字で対応させないのは、添字と列の対応を暗黙の約束にしないためである。
    pub(in crate::renderer) fn 描画発行内訳を作る(&self) -> 描画発行内訳 {
        self.計数集計.内訳を作る(|パス| match パス {
            可視パス::シーン => self.ジオメトリ入力作業領域.len(),
            可視パス::影の距離区分(番号) => self.距離区分別のシャドウ入力作業領域[番号.添字()].len(),
        })
    }

    /// 共有のセットは束が持たないため呼び出し元から受け取る。束が1つも無いフレームでも束縛先が決まることの根拠がこれである。
    pub(in crate::renderer) fn 描画対象入力を作る<'計器>(
        &'計器 self, 共有: 共有セット束縛<'計器>
    ) -> 描画対象入力<'計器> {
        描画対象入力 {
            ジオメトリ: &self.ジオメトリ入力作業領域,
            距離区分別のシャドウ: 距離区分別のシャドウ入力::生成する(&self.距離区分別のシャドウ入力作業領域),
            共有,
        }
    }
}
