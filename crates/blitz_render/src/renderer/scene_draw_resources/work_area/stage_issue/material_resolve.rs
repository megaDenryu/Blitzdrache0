//! 発行が指す材質スロット番号から、大域材質IDと、そのフレームが束縛する資源表世代の中の位置と材質変種キーの組(世代内材質解決)を求める工程。
//! 受け取るのは描画対象の材料とプリミティブ発行1件、返すのは大域材質IDと世代内材質解決である。

use super::描画対象の材料;
use crate::error::{フレーム入力不一致エラー, レンダラーエラー};
use crate::frame_input::プリミティブ描画発行;
use crate::vulkan::material_table::{世代内材質解決, 大域材質ID};

/// 発行が指す材質スロット番号から大域材質IDを求め、そのフレームが束縛する資源表世代の中での位置と材質変種キーへ写す。
/// 世代の一致を材質資源表が確かめるため、束縛した表と別の世代の添字を描画定数へ載せることがない。
/// 材質IDも一緒に返すのは、並べ替えと材質切替の計器が世代に依らない論理的な識別で材質を比べるためである。
/// 番号が資源に無いのは、レンダラーへ載せた材質集合と描画発行が別の原型から来ている状態であり、無言で他の材質を束ねずに失敗させる。
pub(super) fn 材質スロットから大域材質idと世代内材質解決を求める(
    材料: &描画対象の材料<'_>,
    発行: プリミティブ描画発行,
) -> Result<(大域材質ID, 世代内材質解決), レンダラーエラー> {
    let 材質id = 材料
        .資源
        .材質スロット番号から大域材質idを参照する(発行.材質スロット番号())
        .ok_or_else(|| {
            レンダラーエラー::from(フレーム入力不一致エラー::材質スロット未確保 {
                描画対象添字: 材料.対象添字,
                スロット番号: 発行.材質スロット番号(),
            })
        })?;
    let 世代内材質解決 = 材料.入力.材質資源表.束縛した世代で材質を解決する(材料.入力.資源表世代の束縛, 材質id)?;
    Ok((材質id, 世代内材質解決))
}
