//! 描画段階資源のうち大気のベイク済み画像だけを触る操作。触れるフィールドは`大気のベイク済み画像`の1つであり、他の段階の資源へは触れない。
//!
//! 不変条件: `大気のベイク済み画像`が`Some`であることと、フレーム構成に空段階があることは常に一致する。
//! この一致は生成時に決まり、以降変わらない。ここが返す`None`は「この構成では大気のベイク済み画像を作らない」ことだけを意味する。

use super::描画段階資源;
use crate::atmosphere::{スカイビュー観測条件, 大気散乱媒体, 空中遠近観測条件};
use crate::atmosphere_lut_input::大気のベイク済み画像の生成指示;
use crate::error::レンダラーエラー;
use crate::vulkan;
use crate::vulkan::atmosphere_lut::{大気のベイク済み画像の描画入力, 描画入力の材料};
use crate::vulkan::sync::フレームスロット添字;
use crate::vulkan::tracked_device::GPUデバイス;

impl 描画段階資源 {
    /// 大気のベイク済み画像資源を持つフレーム構成かどうか。フレーム描画入力の大気媒体の有無と突き合わせる判定に使う。
    pub(in crate::renderer) fn 大気のベイク済み画像を作るか(&self) -> bool {
        self.大気のベイク済み画像.is_some()
    }

    /// 大気のベイク済み画像の生成パスが束縛する資源。ベイク済み画像資源を持たない構成では`None`を返す。
    /// 空中遠近を焼くかどうかは空段階の方式が決めるため、その判定をこの型が持つ空段階資源へ問う。
    pub(in crate::renderer) fn 大気のベイク済み画像の描画入力を作る(
        &self,
        フレーム添字: フレームスロット添字,
        媒体: &大気散乱媒体,
        条件: (スカイビュー観測条件, 空中遠近観測条件),
        指示: 大気のベイク済み画像の生成指示,
    ) -> Option<大気のベイク済み画像の描画入力> {
        let (スカイビュー条件, 空中遠近条件) = 条件;
        let 材料 = 描画入力の材料 {
            フレーム添字,
            媒体,
            スカイビュー条件,
            空中遠近条件,
            指示,
            空中遠近を参照するか: self.空中遠近を参照するか(),
        };
        self.大気のベイク済み画像.as_ref().map(|一式| 一式.描画入力を作る(&材料))
    }

    /// 空中遠近ボリュームを参照するパスがあるか。大気のベイク済み画像方式で合成を切っていない構成だけが参照する。
    /// 参照しない構成で焼かないのは、誰も参照しないボリュームを焼く時間がそのまま無駄になるためである。
    pub(in crate::renderer) fn 空中遠近を参照するか(&self) -> bool {
        self.空.as_ref().is_some_and(vulkan::sky_stage::空段階資源::空中遠近合成があるか)
    }

    /// そのフレームの大気媒体をベイク済み画像生成用のユニフォームへ書く。ベイク済み画像資源を持たない構成では何もしない。
    /// 前提: 呼び出し元はこのスロットのフェンス待機を済ませている。
    pub(in crate::renderer) fn 大気媒体を書き込む(
        &self,
        device: &GPUデバイス,
        フレーム添字: フレームスロット添字,
        媒体: &大気散乱媒体,
    ) -> Result<(), レンダラーエラー> {
        match &self.大気のベイク済み画像 {
            Some(一式) => 一式.媒体を書き込む(device, フレーム添字, 媒体),
            None => Ok(()),
        }
    }
}
