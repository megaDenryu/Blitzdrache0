//! 遠方環境の照明資源の作り方。受け取るのは器の生成要求と大気のベイク済み画像、返すのはその資源の`Option`である。
//! 作った資源の片付けは呼び出し元の巻き戻しが行う。
//!
//! 空段階の2つと別の工程が持つのは、作る条件が違うためである。あちらはフレーム構成の空段階でも作られ、
//! こちらは照明問い合わせ契約だけで決まる。契約が遠方環境なら大気のベイク済み画像も必ず作られるため
//! (`照明問い合わせ契約::大気のベイク済み画像を作るか`)、ここで大気が無いのは組み立ての順序が壊れていることを意味する。
//! 契約そのものが成立するかどうかは世界方針から契約を作る境界が既に確かめている。

use super::super::生成要求;
use crate::error::レンダラーエラー;
use crate::vulkan;
use crate::vulkan::distant_environment::遠方環境が借りる束縛先;

pub(super) fn 生成する(
    要求: &生成要求<'_>,
    大気: Option<&vulkan::atmosphere_lut::大気のベイク済み画像一式>,
) -> Result<Option<vulkan::indirect_lighting::遠方環境の照明資源>, レンダラーエラー> {
    if !要求.照明問い合わせ契約.遠方環境の資源を作るか() {
        return Ok(None);
    }
    let 大気 = 大気.unwrap_or_else(|| panic!("遠方環境の資源を作ると決まったのに大気のベイク済み画像が無い"));
    let 標本 = 大気.標本の束縛先();
    let シェーダー定数一覧 = 標本.シェーダー定数一覧;
    Ok(Some(vulkan::indirect_lighting::遠方環境の照明資源::生成する(
        要求.device,
        要求.メモリプロパティ,
        遠方環境が借りる束縛先 {
            シェーダー定数一覧: &シェーダー定数一覧,
            遠方環境用スカイビュービュー: 大気.遠方環境用スカイビューのビュー(),
        },
        &要求.シェーダー.遠方環境,
    )?))
}
