//! 空段階の有無だけで決まる2つの資源(大気のベイク済み画像と空段階)の作り方。受け取るのは器の生成要求、
//! 返すのはその資源の`Option`である。作った資源の片付けは呼び出し元の巻き戻しが行う。
//!
//! 2つを同じ工程が持つのは、作る条件がどちらもフレーム構成の空段階1つで決まり、片方だけが在る状態が
//! 成立しないためである。空段階の標本ディスクリプタは大気のベイク済み画像の画像ビューを結ぶ。

use super::super::生成要求;
use crate::atmosphere::大気のベイク済み画像の解像度;
use crate::error::レンダラーエラー;
use crate::frame_composition::フレーム段階;
use crate::vulkan;
use crate::vulkan::sky_stage::{空段階の生成要求, 空段階資源};

/// 大気のベイク済み画像はフレーム構成に空段階があるときだけ作る。空を描かない世界は大気の物理量を1度も焼かない。
pub(super) fn 大気のベイク済み画像を生成する(
    要求: &生成要求<'_>,
) -> Result<Option<vulkan::atmosphere_lut::大気のベイク済み画像一式>, レンダラーエラー> {
    if !要求.構成.含む(フレーム段階::空) {
        return Ok(None);
    }
    Ok(Some(vulkan::atmosphere_lut::大気のベイク済み画像一式::生成する(
        要求.device,
        要求.メモリプロパティ,
        大気のベイク済み画像の解像度::既定値(),
        &要求.シェーダー.大気のベイク済み画像,
    )?))
}

/// 空段階の資源はフレーム構成に空段階があるときだけ作る。無い構成では`None`が「空を描かない」ことを型で表す。
/// 大気のベイク済み画像が無い状態でここへ来ることは無い。どちらもフレーム構成の空段階の有無だけで決まるため、
/// 片方だけがあるのは組み立ての順序が壊れていることを意味する。
pub(super) fn 空を生成する(
    要求: &生成要求<'_>,
    大気のベイク済み画像: Option<&vulkan::atmosphere_lut::大気のベイク済み画像一式>,
) -> Result<Option<空段階資源>, レンダラーエラー> {
    if !要求.構成.含む(フレーム段階::空) {
        return Ok(None);
    }
    let 大気のベイク済み画像 = 大気のベイク済み画像.unwrap_or_else(|| panic!("空段階があるのに大気のベイク済み画像資源が作られていない"));
    Ok(Some(空段階資源::生成する(
        要求.device,
        空段階の生成要求 {
            カラー形式: 要求.シーンカラー形式,
            深度形式: vulkan::depth::深度形式,
            ビューとパスlayout: 要求.セットレイアウト.ビューとパス(),
            シェーダー: &要求.シェーダー.空,
            大気のベイク済み画像,
        },
    )?))
}
