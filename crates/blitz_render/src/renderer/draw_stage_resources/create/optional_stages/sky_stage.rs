//! 大気のベイク済み画像と空の処理位置の作り方。受け取るのは器の生成要求、返すのはその資源の`Option`である。
//! 作った資源の片付けは呼び出し元の巻き戻しが行う。
//!
//! 2つを同じ工程が持つのは、空の処理位置の標本ディスクリプタが大気のベイク済み画像の画像ビューを結び、空の処理位置が
//! あるならベイク済み画像も必ずあるという一方向の依存で結ばれているためである。逆は成り立たない。
//! 遠方環境の契約では空の処理位置が無くてもベイク済み画像を作るため、条件は2つの工程で別々に決まる。

use super::super::生成要求;
use crate::atmosphere::大気のベイク済み画像の解像度;
use crate::error::レンダラーエラー;
use crate::frame_composition::フレームの処理位置;
use crate::vulkan;
use crate::vulkan::sky_stage::{空の処理位置の生成要求, 空の処理位置の資源};

/// 大気のベイク済み画像は、フレーム構成に空の処理位置があるか、照明問い合わせ契約が遠方環境の選択肢のときに作る。
/// 空を描かず間接照明も定数近似の世界だけが、大気の物理量を1度も焼かない。
pub(super) fn 大気のベイク済み画像を生成する(要求: &生成要求<'_>) -> Result<Option<vulkan::atmosphere_lut::大気のベイク済み画像一式>, レンダラーエラー> {
    if !要求.照明問い合わせ契約.大気のベイク済み画像を作るか(要求.構成.含むか(フレームの処理位置::空)) {
        return Ok(None);
    }
    Ok(Some(vulkan::atmosphere_lut::大気のベイク済み画像一式::生成する(
        要求.確保係,
        大気のベイク済み画像の解像度::既定値(),
        &要求.シェーダー.大気のベイク済み画像,
    )?))
}

/// 空の処理位置の資源はフレーム構成に空の処理位置があるときだけ作る。無い構成では`None`が「空を描かない」ことを型で表す。
/// 大気のベイク済み画像が無い状態でここへ来ることは無い。どちらもフレーム構成の空の処理位置の有無だけで決まるため、
/// 片方だけがあるのは組み立ての順序が壊れていることを意味する。
pub(super) fn 空を生成する(要求: &生成要求<'_>, 大気のベイク済み画像: Option<&vulkan::atmosphere_lut::大気のベイク済み画像一式>) -> Result<Option<空の処理位置の資源>, レンダラーエラー> {
    if !要求.構成.含むか(フレームの処理位置::空) {
        return Ok(None);
    }
    let 大気のベイク済み画像 = 大気のベイク済み画像.unwrap_or_else(|| panic!("空の処理位置があるのに大気のベイク済み画像資源が作られていない"));
    Ok(Some(空の処理位置の資源::生成する(
        要求.確保係,
        空の処理位置の生成要求 {
            カラー形式: 要求.シーンカラー形式,
            深度形式: vulkan::depth::深度形式,
            ビューとパスのセットのレイアウト: 要求.セットレイアウト.ビューとパス(),
            シェーダー: &要求.シェーダー.空,
            大気のベイク済み画像,
        },
    )?))
}
