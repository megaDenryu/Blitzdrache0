//! フレーム構成と照明問い合わせ契約しだいで作る段階の資源の生成局面。受け取るのは器の生成要求、返すのは
//! 4つの`Option`を束ねた組である。段階を持たない構成では`None`が「その段階を積まない」ことを型で表す。
//!
//! ここが持つのは4つの資源の生成順と、途中で失敗したときの巻き戻し順である。順序が意味を持つのは、
//! 空段階の標本ディスクリプタも遠方環境の生成ディスクリプタも大気のベイク済み画像の画像ビューと媒体の
//! シェーダー定数を結ぶためであり、大気を先に作って最後に片付ける必要がある。
//! 資源ごとの作り方は、空段階の有無で決まる2つを`sky_stage`、契約で決まる遠方環境を`distant_environment`が持つ。

mod distant_environment;
mod sky_stage;

use super::生成要求;
use crate::error::レンダラーエラー;
use crate::frame_composition::フレーム段階;
use crate::vulkan;
use crate::vulkan::sky_stage::空段階資源;

pub(super) struct 任意段階の資源 {
    pub(super) 空: Option<空段階資源>,
    pub(super) 大気のベイク済み画像: Option<vulkan::atmosphere_lut::大気のベイク済み画像一式>,
    pub(super) 遠方環境の照明: Option<vulkan::indirect_lighting::遠方環境の照明資源>,
    pub(super) 布シャドウ: Option<vulkan::cloth_shadow::布シャドウ資源>,
}

impl 任意段階の資源 {
    /// 生成の逆順で片付ける。空と遠方環境の照明を大気のベイク済み画像より先に置くのは、どちらのディスクリプタも
    /// 大気のベイク済み画像の画像ビューを結んでいるためである。
    fn 片付ける(&self, 要求: &生成要求<'_>) {
        if let Some(布シャドウ) = &self.布シャドウ {
            布シャドウ.破棄する(要求.device);
        }
        if let Some(空) = &self.空 {
            空.破棄する(要求.device);
        }
        if let Some(遠方環境の照明) = &self.遠方環境の照明 {
            遠方環境の照明.破棄する(要求.device);
        }
        if let Some(大気のベイク済み画像) = &self.大気のベイク済み画像 {
            大気のベイク済み画像.破棄する(要求.device);
        }
    }
}

pub(super) fn 組み立てる(要求: &生成要求<'_>) -> Result<任意段階の資源, レンダラーエラー> {
    let mut 資源 = 任意段階の資源 {
        空: None,
        大気のベイク済み画像: sky_stage::大気のベイク済み画像を生成する(要求)?,
        遠方環境の照明: None,
        布シャドウ: None,
    };
    match 大気の上へ積む(要求, &mut 資源) {
        Ok(()) => Ok(資源),
        Err(誤り) => {
            資源.片付ける(要求);
            Err(誤り)
        }
    }
}

/// 大気のベイク済み画像を作った後の3つを順に積む。途中で失敗したら、それまでに積んだぶんは呼び出し元が片付ける。
fn 大気の上へ積む(要求: &生成要求<'_>, 資源: &mut 任意段階の資源) -> Result<(), レンダラーエラー> {
    let 大気 = 資源.大気のベイク済み画像.as_ref();
    資源.遠方環境の照明 = distant_environment::生成する(要求, 大気)?;
    資源.空 = sky_stage::空を生成する(要求, 大気)?;
    資源.布シャドウ = 布シャドウを生成する(要求)?;
    Ok(())
}

/// 布専用シャドウ経路はフレーム構成に布シミュレーション段階があるときだけ作る。無い構成では`None`が「布を描かない」ことを型で表す。
fn 布シャドウを生成する(
    要求: &生成要求<'_>
) -> Result<Option<vulkan::cloth_shadow::布シャドウ資源>, レンダラーエラー> {
    if !要求.構成.含む(フレーム段階::布シミュレーション) {
        return Ok(None);
    }
    Ok(Some(vulkan::cloth_shadow::布シャドウ資源::生成する(
        要求.device,
        要求.セットレイアウト.ビューとパス(),
        &要求.シェーダー.布.シャドウ,
    )?))
}
