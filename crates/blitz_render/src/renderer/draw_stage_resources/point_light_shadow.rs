//! 描画段階資源のうち、点光源の影のパイプラインだけに触れる操作。
//! 触れるのは`点光源の影`のフィールド1つであり、他の段階の資源には触れない。
//!
//! 呼ばれるのは毎フレームの描画対象入力の組み立て時である。

use super::描画段階資源;
use crate::vulkan::frame::点光源の影の束縛;

impl 描画段階資源 {
    /// 点光源の影の面ごとの記録が束縛するパイプラインとレイアウト。灯を1件も持たないフレームでも同じ値を返し、
    /// パスが1本も積まれないことで束縛そのものが起こらない。
    pub(in crate::renderer) fn 点光源の影の束縛を作る(&self) -> 点光源の影の束縛 {
        点光源の影の束縛 {
            pipeline: self.点光源の影.handle,
            layout: self.点光源の影.layout,
        }
    }
}
