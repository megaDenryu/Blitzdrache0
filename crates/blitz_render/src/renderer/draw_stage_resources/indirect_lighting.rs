//! 描画段階資源のうち遠方環境の照明資源だけを触る操作。触れるフィールドは`遠方環境の照明`の1つであり、
//! 他の段階の資源へは触れない。
//!
//! 不変条件: `遠方環境の照明`が`Some`であることと、照明問い合わせ契約が遠方環境の枝であることは常に一致する。
//! この一致は生成時に決まり、以降変わらない。フレーム描画入力の遠方環境の有無との食い違いは型付きエラーにし、
//! 無言で焼かないことも無言で既定の尺度で焼くこともしない(参照: CLAUDE.md「不在・未設定・使用不可」)。
//!
//! 失敗を空エラーで表さないのは、遠方環境の契約が空段階を持たない起動でも成立するためである。この工程は
//! `--no-sky`でも通るため、「空段階を持たない起動では起こらない」と自己定義する層へは載せられない。

use super::描画段階資源;
use crate::atmosphere::{スカイビュー観測条件, 大気散乱媒体};
use crate::distant_environment::input::遠方環境の生成指示;
use crate::error::レンダラーエラー;
use crate::frame_input::フレーム描画入力;
use crate::indirect_lighting::間接照明入力不一致エラー;
use crate::vulkan::atmosphere_lut::遠方環境用スカイビューの焼く条件;
use crate::vulkan::distant_environment::遠方環境の即時定数;
use crate::vulkan::indirect_lighting::{描画入力の材料, 登録する画像, 間接照明の描画入力};
use crate::vulkan::sync::フレームスロット添字;

/// 遠方環境用スカイビューの材料を組むのに要る、そのフレームの条件。引数の列が伸び続けるのを避けて1つに束ねる。
struct 焼き上げの条件<'a> {
    フレーム添字: フレームスロット添字,
    媒体: &'a 大気散乱媒体,
    スカイビュー条件: スカイビュー観測条件,
    即時定数: 遠方環境の即時定数,
    指示: 遠方環境の生成指示,
}

impl 描画段階資源 {
    /// 間接照明の表現の生成パスが束縛する資源。遠方環境の照明資源を持たない契約では`None`を返す。
    ///
    /// 焼く条件のうち観測半径と太陽の天頂余弦を遠方環境の入力から取るのは、遠方環境だけが代表天頂余弦へ
    /// 正規化した条件で焼くためである。大気の入力が持つのは時計の進行で毎フレーム動く連続な条件である
    /// (参照: `crates/blitz_render/src/distant_environment/frame_input.rs`)。
    ///
    /// 前提: この工程はコマンドを記録して送信するフレームでだけ呼ばれる(取得に失敗して見送るフレームはここへ来ない)。
    /// その前提のもとで「まだ1度も焼いていない」を記録するため、実際に焼いた事実と記録が食い違わない。
    pub(in crate::renderer) fn 間接照明の描画入力を作る(
        &mut self,
        フレーム添字: フレームスロット添字,
        入力: &フレーム描画入力<'_>,
    ) -> Result<Option<間接照明の描画入力>, レンダラーエラー> {
        let 遠方環境 = match (self.遠方環境の照明.is_some(), &入力.遠方環境) {
            (true, Some(遠方環境)) => 遠方環境,
            (false, None) => return Ok(None),
            (true, None) => return Err(間接照明入力不一致エラー::遠方環境の入力なし.into()),
            (false, Some(_)) => return Err(間接照明入力不一致エラー::遠方環境の入力が余分.into()),
        };
        let Some(大気入力) = 入力.大気.as_ref() else {
            return Err(間接照明入力不一致エラー::大気の入力なし.into());
        };
        let 条件 = 遠方環境.スカイビュー条件();
        let 即時定数 = 遠方環境の即時定数 {
            観測半径: 条件.観測半径(大気入力.媒体().消散()).値(),
            太陽天頂余弦: 条件.太陽天頂余弦().値(),
            太陽放射照度: 遠方環境.尺度().太陽放射照度(),
            夜空放射輝度: 遠方環境.尺度().夜空放射輝度(),
        };
        let 材料 = self.材料を組む(&焼き上げの条件 {
            フレーム添字,
            媒体: 大気入力.媒体(),
            スカイビュー条件: 条件,
            即時定数,
            指示: 遠方環境.生成指示(),
        })?;
        Ok(self.遠方環境の照明.as_mut().map(|一式| 一式.描画入力を作る(材料)))
    }

    /// 遠方環境用スカイビューの画像と束縛は大気のベイク済み画像一式が所有するため、ここで組んで渡す。
    /// 資源が無いのは組み立ての順序が壊れていることを意味するため、無言で焼かずに型付きの失敗にする。
    fn 材料を組む(&self, 条件: &焼き上げの条件<'_>) -> Result<描画入力の材料, レンダラーエラー> {
        let Some(大気) = self.大気のベイク済み画像.as_ref() else {
            return Err(間接照明入力不一致エラー::大気の資源なし.into());
        };
        let 画像 = 大気.遠方環境用スカイビューの画像入力();
        Ok(描画入力の材料 {
            フレーム添字: 条件.フレーム添字,
            即時定数: 条件.即時定数,
            指示: 条件.指示,
            遠方環境用スカイビューの画像: 登録する画像 {
                画像: 画像.画像,
                ビュー: 画像.ビュー,
                寸法: 画像.形.グラフへ渡す寸法(),
            },
            遠方環境用スカイビューの生成入力: 大気.遠方環境用スカイビューの生成入力(
                &遠方環境用スカイビューの焼く条件 {
                    フレーム添字: 条件.フレーム添字,
                    媒体: 条件.媒体,
                    スカイビュー条件: 条件.スカイビュー条件,
                },
            ),
        })
    }
}
