//! 描画段階資源のうち遠方環境の照明資源だけを触る操作。触れるフィールドは`遠方環境の照明`の1つであり、
//! 他の段階の資源へは触れない。
//!
//! 不変条件: `遠方環境の照明`が`Some`であることと、照明問い合わせ契約が遠方環境の枝であることは常に一致する。
//! この一致は生成時に決まり、以降変わらない。フレーム描画入力の遠方環境の有無との食い違いは型付きエラーにし、
//! 無言で焼かないことも無言で既定の尺度で焼くこともしない(参照: CLAUDE.md「不在・未設定・使用不可」)。

use super::描画段階資源;
use crate::error::{レンダラーエラー, 空エラー};
use crate::frame_input::フレーム描画入力;
use crate::vulkan::distant_environment::遠方環境の即時定数;
use crate::vulkan::indirect_lighting::間接照明の描画入力;
use crate::vulkan::sync::フレームスロット添字;

impl 描画段階資源 {
    /// 間接照明の表現の生成パスが束縛する資源。遠方環境の照明資源を持たない契約では`None`を返す。
    ///
    /// 焼く条件のうち観測半径と太陽の天頂余弦を大気の入力から取るのは、そちらが正本だからである
    /// (参照: `crates/blitz_render/src/distant_environment/frame_input.rs`)。
    ///
    /// 前提: この工程はコマンドを記録して送信するフレームでだけ呼ばれる(取得に失敗して見送るフレームはここへ来ない)。
    /// その前提のもとで「まだ1度も焼いていない」を記録するため、実際に焼いた事実と記録が食い違わない。
    pub(in crate::renderer) fn 間接照明の描画入力を作る(
        &mut self,
        フレーム添字: フレームスロット添字,
        入力: &フレーム描画入力<'_>,
    ) -> Result<Option<間接照明の描画入力>, レンダラーエラー> {
        let 遠方環境 = match (self.遠方環境の照明.is_some(), &入力.遠方環境) {
            (true, Some(遠方環境)) => 遠方環境,
            (false, None) => return Ok(None),
            (資源あり, _) => return Err(入力不一致(資源あり).into()),
        };
        let Some(大気) = 入力.大気.as_ref() else {
            return Err(空エラー::入力不一致("遠方環境を焼く入力があるのに大気媒体が未指定".to_string()).into());
        };
        let 条件 = 大気.スカイビュー条件();
        let 即時定数 = 遠方環境の即時定数 {
            観測半径: 条件.観測半径(大気.媒体().消散()).値(),
            太陽天頂余弦: 条件.太陽天頂余弦().値(),
            太陽放射照度: 遠方環境.尺度().太陽放射照度(),
            夜空放射輝度: 遠方環境.尺度().夜空放射輝度(),
        };
        Ok(self
            .遠方環境の照明
            .as_mut()
            .map(|一式| 一式.描画入力を作る(フレーム添字, 即時定数, 遠方環境.生成指示())))
    }
}

fn 入力不一致(資源あり: bool) -> 空エラー {
    let 文面 = if 資源あり {
        "遠方環境の照明資源がある契約なのに遠方環境の入力が未指定"
    } else {
        "遠方環境の照明資源の無い契約に遠方環境の入力が指定された"
    };
    空エラー::入力不一致(文面.to_string())
}
