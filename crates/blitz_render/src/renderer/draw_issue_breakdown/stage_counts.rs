//! 1つのパスが1フレームに描いたLOD段ごとの個体数。添字が段番号であり、値はその段の描画発行が持つインスタンス数の合計である。
//! 段の総数でなく実際に描いた段までを持つのは、この数の出どころが積んだ描画発行そのものだからである。
//! 同じ群の中で2つ以上の段が同時に非零になることが、個体別LODが効いていることの計数側の証拠になる。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「個体別LOD」

#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct 段別個体数 {
    段ごと: Vec<u64>,
}

impl 段別個体数 {
    pub(crate) fn 一覧から生成する(段ごと: Vec<u64>) -> Self {
        Self { 段ごと }
    }

    pub fn 段ごと(&self) -> &[u64] {
        &self.段ごと
    }

    /// 段別個体数の合計。積んだ描画発行のインスタンス数の総和と一致する。
    pub fn 合計(&self) -> u64 {
        self.段ごと.iter().sum()
    }
}
