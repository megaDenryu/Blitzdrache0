//! 1つのパスが1フレームに行った描画発行の数。発行回数・候補数・可視数・個体数の4つを別々に持つ。
//! 発行回数と個体数を分けるのは、直接インスタンス描画では発行回数が個体数に比例せず、群と段の数だけで決まるためである。
//! 可視数と個体数を分けるのは、前者が可視判定が可視と判じた数、後者が積んだ描画発行のインスタンス数の合計であり、
//! 出どころの違う2つが一致することがそのフレームの整合の証拠になるためである。
//! 可視判定を行わないパスでは候補数・可視数・個体数の3つが等しくなる。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct パス別描画発行 {
    発行数: usize,
    候補数: u64,
    可視数: u64,
    個体数: u64,
}

impl パス別描画発行 {
    pub(crate) fn 生成する(発行数: usize, 候補数: u64, 可視数: u64, 個体数: u64) -> Self {
        Self {
            発行数,
            候補数,
            可視数,
            個体数,
        }
    }

    pub(crate) fn 空() -> Self {
        Self::生成する(0, 0, 0, 0)
    }

    pub fn 発行数(&self) -> usize {
        self.発行数
    }

    pub fn 候補数(&self) -> u64 {
        self.候補数
    }

    pub fn 可視数(&self) -> u64 {
        self.可視数
    }

    pub fn 個体数(&self) -> u64 {
        self.個体数
    }
}
