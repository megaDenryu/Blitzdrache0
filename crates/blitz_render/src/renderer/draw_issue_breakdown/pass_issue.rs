//! 1つのパスが1フレームに行った描画発行の数。発行回数・候補数・可視数・個体数・段別個体数の5つを別々に持つ。
//! 発行回数と個体数を分けるのは、直接インスタンス描画では発行回数が個体数に比例せず、群と非空段の数だけで決まるためである。
//! 可視数と個体数を分けるのは、前者が可視判定が可視と判じた数、後者が積んだ描画発行のインスタンス数の合計であり、
//! 出どころの違う2つが一致することがそのフレームの整合の証拠になるためである。
//! 候補数はどのパスでも同じ全個体数であり、可視数はそのパスの範囲が通した数であるから、パスごとに別々の値になる。
//! 可視判定の対象でない描画対象では候補数・可視数・個体数の3つが等しくなる。
//! 段別個体数は個体数を段へ分解したものであり、合計は常に個体数と一致する。
//! 投入インデックス数は積んだ発行のインデックス数とインスタンス数の積の総和であり、発行数からも個体数からも導けない。
//! 注意: これは頂点段の実行回数そのものではなく、その代理変数である。索引付き描画は頂点キャッシュが効くため、
//! 同じインデックスを共有する三角形の頂点段は1回しか走らないことがある。使えるのは同じ形を使う条件どうしの比較であり、
//! 形の違う原型のあいだで頂点処理量を比べる根拠にはならない
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」)。

use super::stage_counts::段別個体数;
use crate::vulkan::frame::記録側の計数;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct パス別描画発行 {
    発行数: usize,
    候補数: u64,
    可視数: u64,
    個体数: u64,
    段別個体数: 段別個体数,
    投入インデックス数: u64,
    記録側: 記録側の計数,
}

impl パス別描画発行 {
    /// 数え始める前の値。パスごとの配列を埋める途中の初期値として使う。
    pub(crate) fn 空() -> Self {
        Self::生成する(0, 0, 0, 段別個体数::default(), 0, 記録側の計数::default())
    }

    pub(crate) fn 生成する(
        発行数: usize,
        候補数: u64,
        可視数: u64,
        段別個体数: 段別個体数,
        投入インデックス数: u64,
        記録側: 記録側の計数,
    ) -> Self {
        Self {
            発行数,
            候補数,
            可視数,
            個体数: 段別個体数.合計(),
            段別個体数,
            投入インデックス数,
            記録側,
        }
    }

    pub fn 発行数(&self) -> usize {
        self.発行数
    }

    pub fn 候補数(&self) -> u64 {
        self.候補数
    }

    pub fn 可視数(&self) -> u64 {
        self.可視数
    }

    pub fn 個体数(&self) -> u64 {
        self.個体数
    }

    pub fn 段別個体数(&self) -> &段別個体数 {
        &self.段別個体数
    }

    /// このパスが積んだ発行のインデックス数とインスタンス数の積の総和。頂点処理量の代理変数である。
    pub fn 投入インデックス数(&self) -> u64 {
        self.投入インデックス数
    }

    /// 記録が実際にGPUへ積んだ回数。発行数と観測地点が違うため別の型で持つ。
    pub fn 記録側(&self) -> 記録側の計数 {
        self.記録側
    }
}
