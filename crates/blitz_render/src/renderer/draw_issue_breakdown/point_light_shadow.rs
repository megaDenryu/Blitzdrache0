//! 1フレームの点光源の影の記録の内訳。担うのは、面ごとの絞りが何件を判定し何件を通し何回描いたかを1つの値で示すことである。
//!
//! 描画発行内訳と別の型にするのは、あちらが可視ID列の区間を持つパスの形を写した表であり、点光源の影が
//! その列を1つも通らないためである。同じ表へ足すと、可視ID列を読むパスの数と表の行数が食い違う
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断n」)。
//!
//! 判定した数と通った数の両方を持つのは、片方だけでは絞りが効いているかを値から読めないためである。

/// 1フレームの点光源の影の記録の内訳。灯を1件も持たないフレームは4つとも0になる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 点光源の影の記録内訳 {
    記録した面の数: u64,
    面ごとの絞りが判定した発行数: u64,
    絞りを通った発行数: u64,
    描画の発行数: u64,
}

impl 点光源の影の記録内訳 {
    pub(crate) fn 生成する(
        記録した面の数: u64, 面ごとの絞りが判定した発行数: u64, 絞りを通った発行数: u64, 描画の発行数: u64
    ) -> Self {
        Self {
            記録した面の数,
            面ごとの絞りが判定した発行数,
            絞りを通った発行数,
            描画の発行数,
        }
    }

    /// そのフレームに記録した面の数。影を落とす灯の件数の6倍である。
    pub fn 記録した面の数(&self) -> u64 {
        self.記録した面の数
    }

    /// 面ごとの絞りに掛けた発行の総数。記録した面の数×そのフレームの発行の数である。
    pub fn 面ごとの絞りが判定した発行数(&self) -> u64 {
        self.面ごとの絞りが判定した発行数
    }

    /// 絞りを通った発行の総数。判定した数との比が、絞りが落とした割合である。
    pub fn 絞りを通った発行数(&self) -> u64 {
        self.絞りを通った発行数
    }

    /// 実際に積んだ描画の回数。絞りを通った発行はすべて描くため、通った数と一致する。
    /// 別に数えるのは、一致しなくなったときに絞りと記録のどちらが動いたかを値から分けるためである。
    pub fn 描画の発行数(&self) -> u64 {
        self.描画の発行数
    }
}
