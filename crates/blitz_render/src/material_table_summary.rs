//! 公開中の資源表世代の要約。担当するのは、表の中身をレンダラーの外へGPUの型なしで見せることである。
//!
//! 常駐画像数を見せるのは、テクスチャを持たない材質がそれぞれ既定の画素を持つのでなく、世代で共有する
//! 正準フォールバックを指していることを実行の値で確かめるためである。材質が何件あっても、テクスチャを1枚も
//! 持たないシーンの常駐画像は正準フォールバックの3枚だけになる
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「材質レコードとテクスチャ台帳」)。

/// 公開中の資源表世代の版番号と中身の件数。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 材質資源表の要約 {
    世代番号: u32,
    材質件数: usize,
    常駐画像枚数: usize,
}

impl 材質資源表の要約 {
    pub(crate) const fn 生成する(世代番号: u32, 材質件数: usize, 常駐画像枚数: usize) -> Self {
        Self {
            世代番号,
            材質件数,
            常駐画像枚数,
        }
    }

    pub fn 世代番号(self) -> u32 {
        self.世代番号
    }

    pub fn 材質件数(self) -> usize {
        self.材質件数
    }

    pub fn 常駐画像枚数(self) -> usize {
        self.常駐画像枚数
    }
}
