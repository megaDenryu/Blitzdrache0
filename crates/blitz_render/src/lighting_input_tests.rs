#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};

use crate::clustered_lighting::影響半径;
use crate::{ライティング入力エラー, 光強度, 光色, 影入力, 影正射影範囲, 方向光入力, 点光源入力, 環境光係数};

fn 大域位置(x: f64, y: f64, z: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(x), 大域メートル::生成する(y), 大域メートル::生成する(z))
}

fn 妥当な正射影範囲() -> 影正射影範囲 {
    影正射影範囲::生成する(
        メートル::生成する(4.0),
        メートル::生成する(4.0),
        メートル::生成する(0.1),
        メートル::生成する(20.0),
    )
    .unwrap()
}

#[test]
fn 不正な色と強度と環境光係数を拒否する() {
    assert!(matches!(光色::生成する(f32::NAN, 1.0, 1.0), Err(ライティング入力エラー::色不正)));
    assert!(matches!(光強度::生成する(-0.1), Err(ライティング入力エラー::強度不正)));
    assert!(matches!(環境光係数::生成する(1.1), Err(ライティング入力エラー::環境光係数不正)));
}

#[test]
fn 方向光は正規化されて逆方向の位置を作る() {
    let 白 = 光色::生成する(1.0, 1.0, 1.0).unwrap();
    let 強度 = 光強度::生成する(1.0).unwrap();
    let 方向光 = 方向光入力::生成する(-1.0, 0.0, 0.0, 白, 強度).unwrap();
    let 位置 = 方向光.逆方向へ離れた位置(メートル::生成する(10.0));

    assert_eq!(位置.x().値(), 10.0);
    assert_eq!(位置.y().値(), 0.0);
    assert_eq!(位置.z().値(), 0.0);
}

#[test]
fn ゼロ長の方向光を拒否する() {
    let 白 = 光色::生成する(1.0, 1.0, 1.0).unwrap();
    let 強度 = 光強度::生成する(1.0).unwrap();

    assert!(matches!(
        方向光入力::生成する(0.0, 0.0, 0.0, 白, 強度),
        Err(ライティング入力エラー::方向不正)
    ));
}

#[test]
fn 非有限の点光源位置を拒否する() {
    let 白 = 光色::生成する(1.0, 1.0, 1.0).unwrap();
    let 強度 = 光強度::生成する(1.0).unwrap();

    assert!(matches!(
        点光源入力::生成する(大域位置(f64::NAN, 0.0, 0.0), 白, 強度, 半径()),
        Err(ライティング入力エラー::点光源位置不正)
    ));
}

fn 半径() -> 影響半径 {
    影響半径::生成する(メートル::生成する(10.0)).unwrap()
}

#[test]
fn 非有限の影注視点と非正の光源距離を拒否する() {
    assert!(matches!(
        影入力::生成する(大域位置(f64::NAN, 0.0, 0.0), メートル::生成する(10.0), 妥当な正射影範囲()),
        Err(ライティング入力エラー::影注視点不正)
    ));
    assert!(matches!(
        影入力::生成する(大域位置(0.0, 0.0, 0.0), メートル::生成する(0.0), 妥当な正射影範囲()),
        Err(ライティング入力エラー::影光源距離不正)
    ));
}

#[test]
fn 逆転した近遠クリップと非正の半幅を拒否する() {
    let 逆転 = 影正射影範囲::生成する(
        メートル::生成する(4.0),
        メートル::生成する(4.0),
        メートル::生成する(20.0),
        メートル::生成する(0.1),
    );
    assert!(matches!(逆転, Err(ライティング入力エラー::影正射影範囲不正)));

    let 半幅ゼロ = 影正射影範囲::生成する(
        メートル::生成する(0.0),
        メートル::生成する(4.0),
        メートル::生成する(0.1),
        メートル::生成する(20.0),
    );
    assert!(matches!(半幅ゼロ, Err(ライティング入力エラー::影正射影範囲不正)));
}
