//! 束の中のどの個体が動く個体かを、束の読込より前に宣言する型。担当するのは「どの描画対象のどの個体を動く個体にするか」の
//! 指し示しだけであり、その個体がどこへ動くかは持たない。
//!
//! 読込時に宣言する形にしたのは、動く個体だけがフレームスロットごとのホスト可視バッファを持ち、そのバッファを
//! ディスクリプタが結ぶためである。読み込んだ後に動く個体を足す形にすると、結び終わったディスクリプタを
//! 結び直す経路が要る。宣言を1つも持たない束は全対象が読込時に一度だけ書いた静的な個体変換を読み、
//! GPU資源の確保も毎フレームの書き込みも1つも増えない。
//! 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「判断5: 動くオブジェクトはゲーム状態が正本であり、描画へは毎フレーム供給する」

/// 束の中の1体の動く個体の宣言。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 動く個体の宣言 {
    /// 束の中での描画対象の並び順。可視個体選択が描画対象を指す添字と同じ値である。
    pub 描画対象添字: usize,
    /// その描画対象の個体変換列の中での個体の並び順。
    pub 個体添字: u32,
}
