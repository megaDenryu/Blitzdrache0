//! 描画対象素材: 1回の描画発行に必要な配置、詳細段ごとの形状、材質スロットごとのマテリアルを束ねる。
//! 配置は「f64の大域の基準原点」と「基準原点からの相対の静的なf32変換の列」の2つに分ける。大きな平行移動をf32の変換へ入れると、
//! GPUへ渡す前に桁が失われるためである(参照: `_doc/設計/地形とカメラ相対描画.md`「適用点: チャンク由来の描画の基準原点」)。
//! 変換を列で持つのは、インスタンス群が1つの原型を個体ごとの変換で多数描くためである。単一の対象は1件の列になる。

mod instance_transform_list;
mod material_slot_entry;
mod material_slot_list;

use blitz_math::{ローカル, ワールド, 変換, 大域ワールド位置};

pub use instance_transform_list::個体変換列;
pub use material_slot_entry::材質スロット素材;
pub use material_slot_list::材質スロット素材一覧;

use crate::lod_mesh::メッシュ素材;
use crate::lod_mesh::詳細段メッシュ列;
use crate::vertex::頂点;

/// Vulkan型を露出せずに1つの描画対象をレンダラーへ渡す入力。
pub struct 描画対象素材 {
    大域の基準原点: 大域ワールド位置,
    個体変換列: 個体変換列,
    メッシュ列: 詳細段メッシュ列,
    材質スロット素材一覧: 材質スロット素材一覧,
}

impl 描画対象素材 {
    /// `大域の基準原点`は所有チャンクの大域原点、`個体変換列`はその基準原点を基準にした個体ごとの静的な配置である。
    /// 材質を一覧で受けるのは、1つのメッシュが材質スロットごとに違う材質で塗られうるためである。単一材質の対象は要素1件の一覧になる。
    pub fn 生成する(
        大域の基準原点: 大域ワールド位置,
        個体変換列: 個体変換列,
        メッシュ列: 詳細段メッシュ列,
        材質スロット素材一覧: 材質スロット素材一覧,
    ) -> Self {
        Self {
            大域の基準原点,
            個体変換列,
            メッシュ列,
            材質スロット素材一覧,
        }
    }

    /// スキニングの入力となる頂点。スキンは最詳細段だけへ適用するため、段の選択を受け取らない。
    pub fn 最詳細段の頂点一覧(&self) -> &[頂点] {
        self.メッシュ列.最詳細段().頂点一覧()
    }

    pub(crate) fn 大域の基準原点(&self) -> 大域ワールド位置 {
        self.大域の基準原点
    }

    /// 描画対象シェーダー定数が持つ変換。個体が複数あっても係数は共有するため、先頭の個体の変換を代表として使う。
    pub(crate) fn 先頭の個体変換(&self) -> 変換<ローカル, ワールド> {
        self.個体変換列.先頭()
    }

    pub(crate) fn 個体変換一覧(&self) -> &[変換<ローカル, ワールド>] {
        self.個体変換列.一覧()
    }

    pub(crate) fn 段一覧(&self) -> &[メッシュ素材] {
        self.メッシュ列.段一覧()
    }

    pub(crate) fn 材質スロット素材一覧(&self) -> &材質スロット素材一覧 {
        &self.材質スロット素材一覧
    }
}
