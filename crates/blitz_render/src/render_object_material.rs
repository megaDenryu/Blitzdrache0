//! 描画対象素材: 1回の描画発行に必要な配置、形状、マテリアルを束ねる。
//! 配置は「f64の大域アンカー」と「アンカー基準の静的なf32変換」の2つに分ける。大きな平行移動をf32の変換へ入れると、
//! GPUへ渡す前に桁が失われるためである(参照: `_doc/設計/地形とカメラ相対描画.md`「適用点: チャンク由来の描画アンカー」)。

use blitz_math::{ローカル, ワールド, 変換, 大域ワールド位置};

use crate::material::マテリアル素材;
use crate::vertex::頂点;

/// Vulkan型を露出せずに1つの描画対象をレンダラーへ渡す入力。
pub struct 描画対象素材 {
    大域アンカー: 大域ワールド位置,
    ローカルからワールド: 変換<ローカル, ワールド>,
    頂点一覧: Vec<頂点>,
    インデックス一覧: Vec<u32>,
    マテリアル: マテリアル素材,
}

impl 描画対象素材 {
    /// `大域アンカー`は所有チャンクの大域原点、`ローカルからワールド`はそのアンカーを基準にした静的な配置である。
    pub fn 生成する(
        大域アンカー: 大域ワールド位置,
        ローカルからワールド: 変換<ローカル, ワールド>,
        頂点一覧: Vec<頂点>,
        インデックス一覧: Vec<u32>,
        マテリアル: マテリアル素材,
    ) -> Self {
        Self {
            大域アンカー,
            ローカルからワールド,
            頂点一覧,
            インデックス一覧,
            マテリアル,
        }
    }

    pub fn 頂点一覧(&self) -> &[頂点] {
        &self.頂点一覧
    }

    pub(crate) fn 大域アンカー(&self) -> 大域ワールド位置 {
        self.大域アンカー
    }

    pub(crate) fn ローカルからワールド(&self) -> 変換<ローカル, ワールド> {
        self.ローカルからワールド
    }

    pub(crate) fn インデックス一覧(&self) -> &[u32] {
        &self.インデックス一覧
    }

    pub(crate) fn マテリアル(&self) -> &マテリアル素材 {
        &self.マテリアル
    }
}
