//! 描画対象素材: 1回の描画発行に必要な変換、形状、マテリアルを束ねる。

use blitz_math::{ローカル, ワールド, 変換};

use crate::material::マテリアル素材;
use crate::vertex::頂点;

/// Vulkan型を露出せずに1つの描画対象をレンダラーへ渡す入力。
pub struct 描画対象素材 {
    ローカルからワールド: 変換<ローカル, ワールド>,
    頂点一覧: Vec<頂点>,
    インデックス一覧: Vec<u32>,
    マテリアル: マテリアル素材,
}

impl 描画対象素材 {
    pub fn 生成する(
        ローカルからワールド: 変換<ローカル, ワールド>,
        頂点一覧: Vec<頂点>,
        インデックス一覧: Vec<u32>,
        マテリアル: マテリアル素材,
    ) -> Self {
        Self {
            ローカルからワールド,
            頂点一覧,
            インデックス一覧,
            マテリアル,
        }
    }

    pub fn 頂点一覧(&self) -> &[頂点] {
        &self.頂点一覧
    }

    pub(crate) fn ローカルからワールド(&self) -> 変換<ローカル, ワールド> {
        self.ローカルからワールド
    }

    pub(crate) fn インデックス一覧(&self) -> &[u32] {
        &self.インデックス一覧
    }

    pub(crate) fn マテリアル(&self) -> &マテリアル素材 {
        &self.マテリアル
    }
}
