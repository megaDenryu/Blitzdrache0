//! フレーム1枚ぶんの1区間のGPU時間。担当するのは、窓へ入る前の生の値を、どの回の読み取りのどの区間かと一緒に運ぶことである。
//!
//! 窓の集約(平均・中央値・95パーセンタイル)と別に持つのは、集約からは元の列を復元できないためである。
//! 合成区間の分位を後から独立に計算し直して報告値と突き合わせるには、フレームごとの値そのものが要る
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「IIa-1の実装」)。

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct フレーム別の標本 {
    読み取り順: u64,
    区間名: &'static str,
    経過ミリ秒: f64,
}

impl フレーム別の標本 {
    pub(crate) const fn 生成する(読み取り順: u64, 区間名: &'static str, 経過ミリ秒: f64) -> Self {
        Self {
            読み取り順,
            区間名,
            経過ミリ秒,
        }
    }

    /// クエリ結果を読み取った回の通し番号。0から始まり、読み取りは1フレームに1回であるため描画したフレームの順に並ぶ。
    /// 番号が指すのは読み取りを行ったフレームであり、その値を刻んだのは進行中フレーム数だけ前のフレームである。
    pub const fn 読み取り順(self) -> u64 {
        self.読み取り順
    }

    pub const fn 区間名(self) -> &'static str {
        self.区間名
    }

    pub const fn 経過ミリ秒(self) -> f64 {
        self.経過ミリ秒
    }
}
