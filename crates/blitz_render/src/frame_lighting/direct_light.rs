//! 直接光の供給元の判別。担当するのは「そのフレームの直接光がどういう出どころで与えられたか」の1点であり、
//! GPUのレコードの並びも件数も知らない。
//!
//! 現行は方向光1件と点光源1件を値でそのまま持つ`固定`の1枝である。順5の多光源では光源集合のGPU参照を
//! 別の枝として足すため、枝を持たない構造体にしない
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「現行ライティング入力の改鋳(段1で行う)」)。

use crate::lighting_input::{方向光入力, 点光源入力};

pub(crate) enum 直接光入力 {
    固定 {
        方向光: 方向光入力, 点光源: 点光源入力
    },
}
