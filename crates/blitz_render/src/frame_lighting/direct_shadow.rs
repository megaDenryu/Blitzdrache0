//! 直接光の可視性(影)の入力。担当するのは「その方向光の遮蔽をどの資源で判定するか」の1点であり、
//! 多段の分割や正射影の組み立ては持たない(それは`cascade`が持つ)。
//!
//! 可視性を光ごとの値にするのは、大域の「影が有効か」1つへ畳むと順5の複数方向光で
//! 「どの光がどの影資源を見るか」の対応が失われるためである
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「順5(多光源クラスタード)への接続」)。

/// 多段影の資源を指す添字。現行は1組しか存在しないため常に0だが、番兵ではなく実在する資源の位置である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 多段影資源添字(u32);

impl 多段影資源添字 {
    pub(crate) fn 生成する(値: u32) -> Self {
        Self(値)
    }

    pub(crate) fn 値(self) -> u32 {
        self.0
    }
}

/// 1件の直接光の遮蔽の判定方法。「影なし」を添字の番兵で表さず明示の枝で表す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 直接光の可視性 {
    影なし,
    多段影 { 資源添字: 多段影資源添字 },
}

impl 直接光の可視性 {
    /// 多段影の資源を指す枝を作る。渡すのは実在する資源の位置であり、「無し」を表す番兵ではない。
    pub(crate) fn 多段影を指す(資源添字: u32) -> Self {
        Self::多段影 {
            資源添字: 多段影資源添字::生成する(資源添字),
        }
    }
}

#[derive(Debug, Clone, Copy)]
pub(crate) struct 直接影入力 {
    方向光の可視性: 直接光の可視性,
}

/// 現行のシーンが持つ多段影の資源は1組だけであり、方向光はその1組を指す。
const 唯一の多段影資源添字: u32 = 0;

impl 直接影入力 {
    pub(crate) fn 生成する(方向光が影を落とすか: bool) -> Self {
        let 方向光の可視性 = if 方向光が影を落とすか {
            直接光の可視性::多段影を指す(唯一の多段影資源添字)
        } else {
            直接光の可視性::影なし
        };
        Self { 方向光の可視性 }
    }

    pub(crate) fn 方向光の可視性(self) -> 直接光の可視性 {
        self.方向光の可視性
    }
}
