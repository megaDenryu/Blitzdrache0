//! 公開入口から分解形への写しが、4つの成分をそれぞれ正しい枝へ振り分けることの検査。
//! 方向光の可視性が「影の落ち方」だけで決まることをここで固定し、GPUのレコードの検査と切り分ける。

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};

use super::{フレーム照明入力, 照明の有効性, 直接光の可視性, 間接照明入力};
use crate::lighting_input::{
    ライティング入力, 光強度, 光色, 影の落ち方, 影入力, 影正射影範囲, 方向光入力, 点光源入力, 環境光係数
};

#[allow(clippy::unwrap_used)]
fn 素材を作る(影の落ち方: 影の落ち方, 有効: bool) -> ライティング入力 {
    let 色 = 光色::生成する(0.5, 0.6, 0.7).unwrap();
    let 強度 = 光強度::生成する(2.0).unwrap();
    let 方向光 = 方向光入力::生成する(0.0, -1.0, 0.0, 色, 強度).unwrap();
    let 原点 = 大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(0.0), 大域メートル::生成する(0.0));
    let 点光源 = 点光源入力::生成する(原点, 色, 強度).unwrap();
    let 範囲 = 影正射影範囲::生成する(
        メートル::生成する(10.0),
        メートル::生成する(10.0),
        メートル::生成する(1.0),
        メートル::生成する(100.0),
    )
    .unwrap();
    let 影 = 影入力::生成する(原点, メートル::生成する(50.0), 範囲).unwrap();
    ライティング入力::生成する(方向光, 点光源, 環境光係数::生成する(0.25).unwrap(), 影, 影の落ち方, 有効)
}

#[test]
fn 影を落とす入力の方向光は多段影の枝を持つ() {
    let 分解 = フレーム照明入力::ライティング入力から写す(&素材を作る(影の落ち方::落とす, true));
    assert_eq!(分解.直接影().方向光の可視性(), 直接光の可視性::多段影を指す(0));
}

#[test]
fn 影を落とさない入力の方向光は影なしの枝を持つ() {
    let 分解 = フレーム照明入力::ライティング入力から写す(&素材を作る(影の落ち方::落とさない, true));
    assert_eq!(分解.直接影().方向光の可視性(), 直接光の可視性::影なし);
}

#[test]
fn ライティング無効は有効性の枝だけを変え間接照明の係数を保つ() {
    let 分解 = フレーム照明入力::ライティング入力から写す(&素材を作る(影の落ち方::落とす, false));
    assert_eq!(分解.有効性(), 照明の有効性::無効);
    let 間接照明入力::定数近似(係数) = 分解.間接照明();
    assert!((係数.値() - 0.25).abs() < f32::EPSILON);
}
