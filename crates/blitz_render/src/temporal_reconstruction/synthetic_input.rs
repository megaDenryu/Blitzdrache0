//! 検収が時間再構成のパスへ与える合成入力4枚。触れるのは4つの成分列と寸法だけであり、GPUの資源もパスも知らない。
//!
//! 4枚を1つの型で運ぶのは、4枚が同じ寸法でなければ突き合わせが成立しないためである。別々に受け取ると、
//! 1枚だけ寸法の違う組をレンダラーへ渡せてしまい、画像の一部だけが書き換わった状態でCPU正本と比べることになる。
//!
//! 値を生の単精度で持つのは、この型がGPUへそのまま渡る境界だからである。合成入力を組み立てるのは
//! コンポジションルートであり、CPU正本(`blitz_engine::temporal_reconstruction`)の型で組んだ値をここへ開いて渡す。
//!
//! 注意: 深度を含めるのは、棄却の判定が今のフレームの奥行きを深度画像から復元するためである。局所可視性補正の
//! 合成深度の注入を使い回さないのは、あちらが深度プリパスの直後へ積まれ、その後のシーン描画が深度プリパスの方式に
//! よっては同じ画像を書き直すためである。時間再構成が読む地点で値が決まっていることを、この4枚を同じ1本のパスで
//! 書き戻すことで保証する。

use crate::error::フレーム入力不一致エラー;
use crate::local_visibility::画像の寸法;

/// 検収が完全に決めた4枚。並びはいずれも行優先である。
pub struct 時間再構成の合成入力 {
    寸法: 画像の寸法,
    今のフレームの色: Vec<f32>,
    履歴: Vec<f32>,
    動きベクトル: Vec<f32>,
    深度: Vec<f32>,
}

/// 画素あたりの成分数。色と履歴は4成分、動きベクトルは2成分、深度は1成分である。
const 色の成分数: usize = 4;
const 履歴の成分数: usize = 4;
const 動きベクトルの成分数: usize = 2;
const 深度の成分数: usize = 1;

impl 時間再構成の合成入力 {
    pub fn 生成する(
        寸法: 画像の寸法,
        今のフレームの色: Vec<f32>,
        履歴: Vec<f32>,
        動きベクトル: Vec<f32>,
        深度: Vec<f32>,
    ) -> Result<Self, フレーム入力不一致エラー> {
        let 画素数 = 寸法.画素数();
        要素数を確かめる("今のフレームの色", 今のフレームの色.len(), 画素数 * 色の成分数)?;
        要素数を確かめる("履歴", 履歴.len(), 画素数 * 履歴の成分数)?;
        要素数を確かめる("動きベクトル", 動きベクトル.len(), 画素数 * 動きベクトルの成分数)?;
        要素数を確かめる("深度", 深度.len(), 画素数 * 深度の成分数)?;
        Ok(Self {
            寸法,
            今のフレームの色,
            履歴,
            動きベクトル,
            深度,
        })
    }

    pub fn 寸法(&self) -> 画像の寸法 {
        self.寸法
    }

    pub(crate) fn 今のフレームの色(&self) -> &[f32] {
        &self.今のフレームの色
    }

    pub(crate) fn 履歴(&self) -> &[f32] {
        &self.履歴
    }

    pub(crate) fn 動きベクトル(&self) -> &[f32] {
        &self.動きベクトル
    }

    pub(crate) fn 深度(&self) -> &[f32] {
        &self.深度
    }
}

/// 要素数が合わない組を無言で受けない。短い側で転送を打ち切ると画像の一部だけが書き換わり、
/// 残りの画素は本番の描画結果のままCPU正本と突き合わされる。
fn 要素数を確かめる(項目: &'static str, 与えた: usize, 期待: usize) -> Result<(), フレーム入力不一致エラー> {
    if 与えた == 期待 {
        return Ok(());
    }
    Err(フレーム入力不一致エラー::合成入力の要素数不一致 { 項目, 与えた, 期待 })
}
