//! 提示1件ごとの実表示観測。観測のために描画ループを止めた時間を必ず一緒に持つ。

/// 提示1件分の表示観測。
///
/// 注意: 間隔は「1つ前の観測から今回の観測まで」であり、提示1件ぶんの表示間隔に対応する。
/// 停止時間msが0に近い観測は、待機を呼ぶ前に既に表示されていたことを意味し、観測時刻は実表示時刻より
/// 後ろへずれる。実表示間隔として読む前に停止時間msの分布を必ず確認すること。
#[derive(Debug, Clone, Copy)]
pub enum 実表示観測 {
    表示を観測した { 前回からの間隔ms: f64, 停止時間ms: f64 }, // 停止時間msはこの観測のために描画ループを止めていた時間である。
    待機が時間切れになった { 停止時間ms: f64 },                // 待機上限まで表示されなかった。間隔は得られていない。
}

impl 実表示観測 {
    /// 表示間隔(ミリ秒)。時間切れでは`None`を返す。
    pub fn 前回からの間隔ms(self) -> Option<f64> {
        match self {
            Self::表示を観測した { 前回からの間隔ms, .. } => Some(前回からの間隔ms),
            Self::待機が時間切れになった { .. } => None,
        }
    }

    /// この観測のために描画ループを止めていた時間(ミリ秒)。
    pub fn 停止時間ms(self) -> f64 {
        match self {
            Self::表示を観測した { 停止時間ms, .. } | Self::待機が時間切れになった { 停止時間ms } => 停止時間ms,
        }
    }
}
