//! パス別区間の配置の検査が、正典順にそろった配置を受理して崩れた配置を個別のエラーで拒むことの検査。
//! 拒む条件を1件ずつ書くのは、どれか1つの条件を落としても別の条件が代わりに拾い、検査が緩んだことに気づけないためである。

#![allow(clippy::unwrap_used)]

use super::パス区間が列を隙間なく埋めるかを検査する;
use crate::error::レンダラーエラー;
use crate::visible_instance_selection::pass_range::パス別描画範囲;
use crate::visible_instance_selection::stage_range::段別描画範囲;
use crate::visible_instance_selection::visible_pass::{可視ID列を読むパス数, 可視パス};
use crate::visible_instance_selection::可視ID列エラー;

/// 段ごとの「個体数とパス別描画数」から、正典順(パスを外・段を内)に隙間なく並ぶ段の一覧と列の長さを作る。
fn 正典順に並べる(段一覧: &[(u32, [u32; 可視ID列を読むパス数])]) -> (Vec<段別描画範囲>, usize) {
    let mut 開始一覧: Vec<[u32; 可視ID列を読むパス数]> = vec![[0; 可視ID列を読むパス数]; 段一覧.len()];
    let mut 累計 = 0u32;
    for パス in 可視パス::全パス() {
        for (段番号, (_, 描画数一覧)) in 段一覧.iter().enumerate() {
            開始一覧[段番号][パス.添字()] = 累計;
            累計 += 描画数一覧[パス.添字()];
        }
    }
    let 範囲一覧 = 段一覧
        .iter()
        .zip(&開始一覧)
        .map(|((個体数, 描画数), 開始)| 段を作る(*個体数, std::array::from_fn(|添字| (開始[添字], 描画数[添字]))))
        .collect();
    (範囲一覧, usize::try_from(累計).unwrap())
}

/// パスごとの(開始, 描画数)をそのまま持つ段。並びを意図的に崩した配置を書くために使う。
fn 段を作る(個体数: u32, 区間: [(u32, u32); 可視ID列を読むパス数]) -> 段別描画範囲 {
    段別描画範囲::生成する(個体数, 区間.map(|(開始, 描画数)| パス別描画範囲::生成する(開始, 描画数)))
}

fn 誤り(段一覧: &[段別描画範囲], 列の長さ: usize) -> 可視ID列エラー {
    match パス区間が列を隙間なく埋めるかを検査する(段一覧, 列の長さ) {
        Err(レンダラーエラー::可視ID列不正(誤り)) => 誤り,
        その他 => panic!("可視ID列エラーを期待したが{その他:?}だった"),
    }
}

#[test]
fn 正典順にそろった区間を受理する() {
    let (範囲一覧, 列の長さ) = 正典順に並べる(&[(4, [3, 4, 2, 0, 1]), (5, [5, 0, 5, 5, 0])]);
    パス区間が列を隙間なく埋めるかを検査する(&範囲一覧, 列の長さ).unwrap();
}

/// どのパスにも1体も描かない段があっても並びは崩れない。群がすべての視錐台の外にあるフレームの形である。
#[test]
fn 描画数が全パス0の段を含む配置を受理する() {
    let (範囲一覧, 列の長さ) = 正典順に並べる(&[(3, [0; 可視ID列を読むパス数]), (2, [2, 0, 1, 0, 0])]);
    パス区間が列を隙間なく埋めるかを検査する(&範囲一覧, 列の長さ).unwrap();
}

/// 可視個体選択を持たない対象の配置も同じ検査を通る。恒等の列をパス数ぶん繰り返した中身と並びが一致するためである。
#[test]
fn 全個体を描く配置は正典順の並びになっている() {
    let 段一覧 = [段別描画範囲::全個体を描く(3)];
    パス区間が列を隙間なく埋めるかを検査する(&段一覧, 3 * 可視ID列を読むパス数).unwrap();
}

#[test]
fn 段を1つも持たない配置を拒む() {
    assert_eq!(誤り(&[], 0), 可視ID列エラー::段なし);
}

#[test]
fn 描画数の合計が列の長さと違えば拒む() {
    let (範囲一覧, _) = 正典順に並べる(&[(2, [1, 1, 0, 0, 0])]);
    assert_eq!(誤り(&範囲一覧, 5), 可視ID列エラー::区間の合計が列の長さと不一致 { 合計: 2, 列の長さ: 5 });
}

/// 距離区分0の区間がシーンの区間の終端から始まらない配置。パスの区間のあいだに隙間が空く形である。
#[test]
fn パスの区間が連続していなければ拒む() {
    let 段一覧 = [段を作る(2, [(0, 2), (3, 0), (3, 0), (3, 0), (3, 0)])];
    assert!(matches!(誤り(&段一覧, 2), 可視ID列エラー::パス区間が連続でない { .. }));
}

/// 同じパスの中で段の区間が連続しない配置。段0の描画数が1なのに段1の開始が2から始まる。
#[test]
fn 同じパスの中で段の区間が連続していなければ拒む() {
    let 一段目 = 段を作る(1, [(0, 1); 可視ID列を読むパス数]);
    let 二段目 = 段を作る(1, [(2, 1); 可視ID列を読むパス数]);
    assert!(matches!(誤り(&[一段目, 二段目], 2), 可視ID列エラー::パス区間が連続でない { .. }));
}

#[test]
fn 段の描画数が個体数を超えれば拒む() {
    let 段一覧 = [段を作る(1, [(0, 2), (2, 0), (2, 0), (2, 0), (2, 0)])];
    assert!(matches!(誤り(&段一覧, 2), 可視ID列エラー::段の描画数超過 { .. }));
}
