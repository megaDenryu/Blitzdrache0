//! パスごとの区間が可視ID列を正典順に隙間なく重なりなく埋めていることの検査。
//! 受け取るのは1つの描画対象ぶんの段の範囲一覧とその対象のID列の長さ、返すのは受理か型付きエラーかである。
//!
//! 正典順はパス(シーン→距離区分0から距離区分3)を外、段番号を内に置いた順である。この順で描画数を足し合わせた値が
//! 次の区間の開始と一致し、最後の合計が列の長さと一致することは、区間が列を覆い尽くしどこも重なっていないことと同値である。
//! 区間が重なれば2つのパスが同じ位置を読み、隙間が空けば誰も読まない要素が列に残って書き込み側の誤りが隠れる。
//!
//! 4区分の並びの検査(シーンが段の先頭から始まりシャドウが中央2区分を占めること)の後継である。距離区分間のIDの重複を
//! 許した時点で「段の内側の区分の順序」という概念そのものが無くなったため、パスごとの区間の連続性だけを見る形へ替えた。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」

use super::stage_range::段別描画範囲;
use super::visible_pass::可視パス;
use super::可視ID列エラー;
use crate::error::レンダラーエラー;

#[cfg(test)]
mod interval_layout_tests;

pub(super) fn パス区間が列を隙間なく埋めるかを検査する(
    段範囲一覧: &[段別描画範囲],
    列の長さ: usize,
) -> Result<(), レンダラーエラー> {
    if 段範囲一覧.is_empty() {
        return Err(可視ID列エラー::段なし.into());
    }
    let mut 合計 = 0u32;
    for パス in 可視パス::全パス() {
        for (段番号, 段) in 段範囲一覧.iter().enumerate() {
            let 区間 = 段.パス(パス);
            if 区間.開始() != 合計 {
                return Err(可視ID列エラー::パス区間が連続でない {
                    パス,
                    段番号,
                    開始: 区間.開始(),
                    期待: 合計,
                }
                .into());
            }
            if 区間.描画数() > 段.個体数() {
                return Err(可視ID列エラー::段の描画数超過 {
                    パス,
                    段番号,
                    描画数: 区間.描画数(),
                    個体数: 段.個体数(),
                }
                .into());
            }
            合計 = 合計.saturating_add(区間.描画数());
        }
    }
    if usize::try_from(合計).is_ok_and(|値| 値 == 列の長さ) {
        return Ok(());
    }
    Err(可視ID列エラー::区間の合計が列の長さと不一致 { 合計, 列の長さ }.into())
}
