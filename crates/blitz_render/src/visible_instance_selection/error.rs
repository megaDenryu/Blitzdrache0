//! 可視ID列と段別描画範囲の入力が満たすべき条件が破れたときの型付きエラー。
//! いずれも呼び出し元の作り方の誤りであり、無言で切り詰めたり無視したりせず失敗させる。

use thiserror::Error;

#[derive(Debug, Error, Clone, Copy, PartialEq, Eq)]
pub enum 可視ID列エラー {
    /// 可視個体選択が指す区間が、同じフレームで渡された可視ID列の外を指した。
    #[error("可視ID区間が範囲外である: 開始{開始}、可視ID列の長さ{列の長さ}")]
    区間が範囲外 { 開始: usize, 列の長さ: usize },

    /// 可視個体選択が指す段の区間が、同じフレームで渡された段別描画範囲の列の外を指した。
    #[error("段範囲の区間が範囲外である: 開始{開始}、段別描画範囲の列の長さ{列の長さ}")]
    段範囲区間が範囲外 { 開始: usize, 列の長さ: usize },

    /// 段を1つも持たない選択が来た。原型は必ず1段以上を持つため、0段は組み立て側の誤りである。
    #[error("段別描画範囲を1つも持たない可視個体選択が来た")]
    段なし,

    /// 段別描画範囲が可視ID列を隙間なく順に埋めていない。シーンとシャドウは同じ開始位置から違う件数を描くため、
    /// 範囲が重なるか隙間が空くと、一方のパスが他方の段の個体を描くことになる。
    #[error("段{段番号}の開始{開始}が直前の段までの合計{期待}と一致しない")]
    段範囲が連続でない { 段番号: usize, 開始: u32, 期待: u32 },

    /// 段の可視数がその段の個体数を超えた。可視判定はその段の個体の部分集合しか返さない。
    #[error("段{段番号}の可視数{可視数}が段の個体数{個体数}を超えた")]
    段の可視数超過 { 段番号: usize, 可視数: u32, 個体数: u32 },

    /// シーンパスの範囲が段の先頭から始まっていない。4区分の並びではシーンの可視個体が段の先頭側を占めるため、
    /// 開始が段の開始と違えば並べ替えの側が区分の順序を崩している。
    #[error("段{段番号}のシーン範囲の開始{シーン開始}が段の開始{段開始}と一致しない")]
    シーン範囲が段の先頭でない {
        段番号: usize, シーン開始: u32, 段開始: u32
    },

    /// シャドウパスの範囲が4区分の並びに合わない。シャドウの範囲は「両方可視」の区分から始まって
    /// 「シャドウのみ可視」の区分で終わるため、開始は段の開始以上かつシーン範囲の終端以下、
    /// 終端はシーン範囲の終端以上かつ段の終端以下になる。シーン範囲の終端は「両方可視」の区分の終端でもあり、
    /// シャドウの終端がそこに届かない範囲は「両方可視」の個体をシャドウから落とす。
    /// これが破れると、一方のパスが他方の区分の個体を描く。
    #[error("段{段番号}のシャドウ範囲[{シャドウ開始}, {シャドウ終端})が4区分の並び(段[{段開始}, {段終端})、シーン終端{シーン終端})に収まらない")]
    シャドウ範囲が4区分に合わない {
        段番号: usize,
        シャドウ開始: u32,
        シャドウ終端: u32,
        シーン終端: u32,
        段開始: u32,
        段終端: u32,
    },

    /// 段別個体数の合計が可視ID列の長さと違う。合計が足りなければシャドウパスが個体を落としたことになる。
    #[error("段別個体数の合計{合計}が可視ID列の長さ{列の長さ}と一致しない")]
    段別個体数の合計不一致 { 合計: u32, 列の長さ: usize },

    /// 書き込む可視ID列の長さがその描画対象の個体数と違う。列は全個体の並べ替えであり、長さは常に個体数に等しい。
    #[error("可視ID列の長さ{列の長さ}が描画対象の個体数{個体数}と一致しない")]
    列の長さ不一致 { 列の長さ: usize, 個体数: u32 },

    /// 書き込む可視ID列が確保した容量を超えた。容量は個体数とパス数の積であり、1個体が全パスへ現れても収まる。
    /// 超える列は組み立て側が同じ個体を同じパスへ二重に積んだか、区間の配置を誤ったことを意味する。
    #[error("可視ID列の長さ{列の長さ}が確保容量{容量件数}件を超えた")]
    容量超過 { 列の長さ: usize, 容量件数: usize },

    /// 可視ID列に、その描画対象の個体数以上の添字が入っていた。シーンとシャドウの頂点シェーダーはこの添字で
    /// 個体変換のストレージバッファを参照するため、そのまま書くとGPUが確保の外を読む。
    #[error("可視ID{可視id}が描画対象の個体数{個体数}以上である")]
    個体数外の可視ID { 可視id: u32, 個体数: u32 },

    /// 可視ID列に同じ添字が2回以上入っていた。列は全個体の並べ替えであり、長さと値の検査を通っても重複があれば
    /// どこかの個体が列から漏れる。漏れた個体はシーンパスにもシャドウパスにも描かれない。
    #[error("可視ID{可視id}が同じ可視ID列に2回以上現れた")]
    重複する可視ID { 可視id: u32 },

    /// 個体が1体だけの描画対象へ、共有列の内容と矛盾する可視ID列が与えられた。単一個体の対象は束が共有する
    /// 固定の列を読むため、書き込む宛先を持たない。
    #[error("個体が1体だけの描画対象には可視ID列を書き込めない")]
    書き込み先なし,
}
