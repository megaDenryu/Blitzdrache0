//! 可視ID列の入力が満たすべき条件が破れたときの型付きエラー。
//! いずれも呼び出し元の作り方の誤りであり、無言で切り詰めたり無視したりせず失敗させる。

use thiserror::Error;

#[derive(Debug, Error, Clone, Copy, PartialEq, Eq)]
pub enum 可視ID列エラー {
    /// 可視個体選択が指す区間が、同じフレームで渡された可視ID列の外を指した。
    #[error("可視ID区間が範囲外である: 開始{開始}、可視ID列の長さ{列の長さ}")]
    区間が範囲外 { 開始: usize, 列の長さ: usize },

    /// 可視数がその描画対象の個体数を超えた。可視判定は個体の部分集合しか返さないため、超えるのは呼び出し元の誤りである。
    #[error("可視数{可視数}が描画対象の個体数{個体数}を超えた")]
    可視数超過 { 可視数: usize, 個体数: u32 },

    /// 可視ID列に、その描画対象の個体数以上の添字が入っていた。シーンの頂点シェーダーはこの添字で個体変換のストレージバッファを
    /// 引くため、そのまま書くとGPUが確保の外を読む。区間の検査は列の長さしか見ておらず、値そのものはここでしか見られない。
    #[error("可視ID{可視id}が描画対象の個体数{個体数}以上である")]
    個体数外の可視ID { 可視id: u32, 個体数: u32 },

    /// 個体が1体だけの描画対象へ可視個体選択が与えられた。単一個体の対象は束が共有する固定の列を読むため、書き込む宛先を持たない。
    #[error("個体が1体だけの描画対象には可視ID列を書き込めない")]
    書き込み先なし,
}
