//! 可視ID列と段別描画範囲の入力が満たすべき条件が破れたときの型付きエラー。
//! いずれも呼び出し元の作り方の誤りであり、無言で切り詰めたり無視したりせず失敗させる。

use thiserror::Error;

use super::visible_pass::可視パス;

#[derive(Debug, Error, Clone, Copy, PartialEq, Eq)]
pub enum 可視ID列エラー {
    /// 可視個体選択が指す区間が、同じフレームで渡された可視ID列の外を指した。
    #[error("可視ID区間が範囲外である: 開始{開始}、可視ID列の長さ{列の長さ}")]
    区間が範囲外 { 開始: usize, 列の長さ: usize },

    /// 可視個体選択が指す段の区間が、同じフレームで渡された段別描画範囲の列の外を指した。
    #[error("段範囲の区間が範囲外である: 開始{開始}、段別描画範囲の列の長さ{列の長さ}")]
    段範囲区間が範囲外 { 開始: usize, 列の長さ: usize },

    /// 段を1つも持たない選択が来た。原型は必ず1段以上を持つため、0段は組み立て側の誤りである。
    #[error("段別描画範囲を1つも持たない可視個体選択が来た")]
    段なし,

    /// パスごとの区間が可視ID列を正典順に隙間なく埋めていない。区間が重なると2つのパスが同じ位置を読み、
    /// 隙間が空くと誰も読まない領域が残って書き込みの側の誤りが隠れる。
    #[error("{}の段{段番号}の開始{開始}が正典順の直前までの合計{期待}と一致しない", パス.名前())]
    パス区間が連続でない {
        パス: 可視パス, 段番号: usize, 開始: u32, 期待: u32
    },

    /// あるパスの段の描画数がその段の個体数を超えた。可視判定はその段の個体の部分集合しか返さない。
    #[error("{}の段{段番号}の描画数{描画数}が段の個体数{個体数}を超えた", パス.名前())]
    段の描画数超過 {
        パス: 可視パス,
        段番号: usize,
        描画数: u32,
        個体数: u32,
    },

    /// 全パス全段の描画数の合計が可視ID列の長さと違う。区間が覆わない要素が列に残るか、区間が列の外を指す。
    #[error("パス別区間の描画数の合計{合計}が可視ID列の長さ{列の長さ}と一致しない")]
    区間の合計が列の長さと不一致 { 合計: u32, 列の長さ: usize },

    /// 段別個体数の合計がその描画対象の個体数と違う。段はその対象の全個体を分割したものであり、
    /// 合計が欠ければどの段からも漏れた個体が出て、その個体はどのパスにも描かれない。
    #[error("段別個体数の合計{合計}が描画対象の個体数{個体数}と一致しない")]
    段別個体数の合計不一致 { 合計: u32, 個体数: u32 },

    /// 書き込む可視ID列が確保した容量を超えた。容量は個体数とパス数の積であり、1個体が全パスへ現れても収まる。
    /// 超える列は組み立て側が同じ個体を同じパスへ二重に積んだか、区間の配置を誤ったことを意味する。
    #[error("可視ID列の長さ{列の長さ}が確保容量{容量件数}件を超えた")]
    容量超過 { 列の長さ: usize, 容量件数: usize },

    /// 可視ID列に、その描画対象の個体数以上の添字が入っていた。シーンとシャドウの頂点シェーダーはこの添字で
    /// 個体変換のストレージバッファを参照するため、そのまま書くとGPUが確保の外を読む。
    #[error("可視ID{可視id}が描画対象の個体数{個体数}以上である")]
    個体数外の可視ID { 可視id: u32, 個体数: u32 },

    /// 1つのパスの区間の中に同じ添字が2回以上入っていた。距離区分をまたいだ重複は正しい影に必要だが、
    /// 同じパスの中の重複はその個体を二重に描き、代わりに別の個体を落としたことを意味する。
    #[error("可視ID{可視id}が{}の区間に2回以上現れた", パス.名前())]
    パス内で重複する可視ID { パス: 可視パス, 可視id: u32 },

    /// 個体が1体だけの描画対象へ、共有列の内容と矛盾する可視ID列が与えられた。単一個体の対象は束が共有する
    /// 値0だけの列を読むため、書き込む宛先を持たない。
    #[error("個体が1体だけの描画対象には可視ID列を書き込めない")]
    書き込み先なし,
}
