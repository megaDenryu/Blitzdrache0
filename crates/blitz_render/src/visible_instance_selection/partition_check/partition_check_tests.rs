//! 4区分の並びの検査が、正しい並びを受理して崩れた並びを個別のエラーで拒むことの検査。
//! 拒む条件を1件ずつ書くのは、どれか1つの条件を落としても別の条件が代わりに拾ってしまい、
//! 検査が緩んだことに気づけなくなるためである。

#![allow(clippy::unwrap_used)]

use super::段範囲が列を隙間なく埋めるかを検査する;
use crate::error::レンダラーエラー;
use crate::visible_instance_selection::pass_range::パス別描画範囲;
use crate::visible_instance_selection::stage_range::段別描画範囲;
use crate::visible_instance_selection::可視ID列エラー;

/// 4区分の件数`[シーンのみ][両方][シャドウのみ][不可視]`から、その並びに従う段を作る。
fn 区分から段を作る(開始: u32, 区分: [u32; 4]) -> 段別描画範囲 {
    let [シーンのみ, 両方, シャドウのみ, 不可視] = 区分;
    段を作る(
        開始,
        シーンのみ + 両方 + シャドウのみ + 不可視,
        (開始, シーンのみ + 両方),
        (開始 + シーンのみ, 両方 + シャドウのみ),
    )
}

fn 段を作る(開始: u32, 個体数: u32, シーン: (u32, u32), シャドウ: (u32, u32)) -> 段別描画範囲 {
    段別描画範囲::生成する(
        開始,
        個体数,
        パス別描画範囲::生成する(シーン.0, シーン.1),
        パス別描画範囲::生成する(シャドウ.0, シャドウ.1),
    )
}

fn 誤り(段一覧: &[段別描画範囲], 列の長さ: usize) -> 可視ID列エラー {
    match 段範囲が列を隙間なく埋めるかを検査する(段一覧, 列の長さ) {
        Err(レンダラーエラー::可視ID列不正(誤り)) => 誤り,
        その他 => panic!("可視ID列エラーを期待したが{その他:?}だった"),
    }
}

#[test]
fn 四区分がそろった段を受理する() {
    let 段一覧 = [区分から段を作る(0, [1, 2, 3, 4]), 区分から段を作る(10, [0, 5, 0, 0])];
    段範囲が列を隙間なく埋めるかを検査する(&段一覧, 15).unwrap();
}

#[test]
fn 空の区分を含む段も受理する() {
    let 段一覧 = [区分から段を作る(0, [0, 0, 0, 0]), 区分から段を作る(0, [2, 0, 0, 0])];
    段範囲が列を隙間なく埋めるかを検査する(&段一覧, 2).unwrap();
}

#[test]
fn 段の合計が列の長さと違えば拒む() {
    let 段一覧 = [区分から段を作る(0, [1, 1, 1, 1])];
    assert_eq!(誤り(&段一覧, 5), 可視ID列エラー::段別個体数の合計不一致 { 合計: 4, 列の長さ: 5 });
}

#[test]
fn 段の範囲が連続していなければ拒む() {
    let 段一覧 = [区分から段を作る(0, [1, 0, 0, 0]), 区分から段を作る(2, [1, 0, 0, 0])];
    assert!(matches!(誤り(&段一覧, 2), 可視ID列エラー::段範囲が連続でない { .. }));
}

#[test]
fn シーン範囲が段の先頭から始まらなければ拒む() {
    let 段一覧 = [段を作る(0, 4, (1, 2), (1, 2))];
    assert!(matches!(誤り(&段一覧, 4), 可視ID列エラー::シーン範囲が段の先頭でない { .. }));
}

#[test]
fn シーンの描画数が段の個体数を超えれば拒む() {
    let 段一覧 = [段を作る(0, 2, (0, 3), (0, 2))];
    assert!(matches!(誤り(&段一覧, 2), 可視ID列エラー::段の可視数超過 { .. }));
}

/// シャドウの開始がシーンの終端を越えると、2つの区分のあいだに隙間ができて「両方可視」の個体が
/// シャドウから漏れる。4区分の並びではこの2つの区分は必ず接する。
#[test]
fn シャドウ範囲がシーン終端より後ろから始まれば拒む() {
    let 段一覧 = [段を作る(0, 4, (0, 1), (2, 2))];
    assert!(matches!(誤り(&段一覧, 4), 可視ID列エラー::シャドウ範囲が4区分に合わない { .. }));
}

/// シャドウの終端がシーンの終端に届かないと、シーンの終端が同時に「両方可視」の区分の終端でもあることと矛盾し、
/// 「両方可視」の個体がシャドウから漏れる。他の条件を1つも破らない範囲でこの条件だけを破る。
#[test]
fn シャドウ範囲がシーン終端より前で終われば拒む() {
    let 段一覧 = [段を作る(0, 4, (0, 4), (1, 1))];
    assert!(matches!(誤り(&段一覧, 4), 可視ID列エラー::シャドウ範囲が4区分に合わない { .. }));
}

#[test]
fn シャドウ範囲が段の終端を越えれば拒む() {
    let 段一覧 = [段を作る(0, 3, (0, 2), (1, 3))];
    assert!(matches!(誤り(&段一覧, 3), 可視ID列エラー::シャドウ範囲が4区分に合わない { .. }));
}
