//! 1つのLOD段の中で、1つのパスが描く連続範囲。開始はその描画対象の可視ID列の先頭からの相対位置であり、
//! そのまま描画発行の先頭インスタンスに、描画数がインスタンス数になる。
//! シーンとシャドウが別々の開始を持つのは、段の範囲の内側を4つの区分へ並べたときに、
//! 2つのパスの可視集合がそれぞれ1つの連続範囲になり、開始位置が区分の境目で食い違うためである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「描画発行」

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct パス別描画範囲 {
    開始: u32,
    描画数: u32,
}

impl パス別描画範囲 {
    pub fn 生成する(開始: u32, 描画数: u32) -> Self {
        Self { 開始, 描画数 }
    }

    pub fn 開始(self) -> u32 {
        self.開始
    }

    pub fn 描画数(self) -> u32 {
        self.描画数
    }

    /// 範囲の終端。飽和加算にするのは、u32の上限を超える入力を検査が範囲外として弾けるようにするためである。
    /// 折り返した値を返すと、外にある範囲が内側に見える。
    pub(super) fn 終端(self) -> u32 {
        self.開始.saturating_add(self.描画数)
    }
}
