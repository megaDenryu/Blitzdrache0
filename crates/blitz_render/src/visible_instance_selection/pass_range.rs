//! 1つのLOD段の中で、1つのパスが描く連続範囲。開始はその描画対象の可視ID列の先頭からの相対位置であり、
//! そのまま描画発行の先頭インスタンスに、描画数がインスタンス数になる。
//! パスごとに別々の開始を持つのは、列がパスの正典順に区間を並べるため、同じ段でもパスによって位置が離れるからである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct パス別描画範囲 {
    開始: u32,
    描画数: u32,
}

impl パス別描画範囲 {
    pub fn 生成する(開始: u32, 描画数: u32) -> Self {
        Self { 開始, 描画数 }
    }

    pub fn 開始(self) -> u32 {
        self.開始
    }

    pub fn 描画数(self) -> u32 {
        self.描画数
    }
}
