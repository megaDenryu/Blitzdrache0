//! 1つのLOD段が可視ID列の中で占める範囲。開始はその描画対象のID列の先頭からの相対位置である。
//! 段の内側は`[シーンのみ可視][両方可視][シャドウのみ可視][どちらも不可視]`の順に並ぶため、
//! シーンパスが描く範囲は段の先頭から「シーンのみ+両方」、シャドウパスが描く範囲は「両方」の開始から
//! 「両方+シャドウのみ」になる。任意に交差する2つの可視集合を、どちらも1本の列の中の連続範囲で表せる。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「描画発行」

use super::pass_range::パス別描画範囲;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 段別描画範囲 {
    開始: u32,
    個体数: u32,
    シーン: パス別描画範囲,
    シャドウ: パス別描画範囲,
}

impl 段別描画範囲 {
    pub fn 生成する(開始: u32, 個体数: u32, シーン: パス別描画範囲, シャドウ: パス別描画範囲) -> Self {
        Self {
            開始,
            個体数,
            シーン,
            シャドウ,
        }
    }

    /// 可視判定を持たない描画対象の段。両パスがその段の全個体を先頭から描く。
    pub fn 全個体を描く(開始: u32, 個体数: u32) -> Self {
        Self::生成する(
            開始,
            個体数,
            パス別描画範囲::生成する(開始, 個体数),
            パス別描画範囲::生成する(開始, 個体数),
        )
    }

    pub fn 開始(self) -> u32 {
        self.開始
    }

    pub fn 個体数(self) -> u32 {
        self.個体数
    }

    pub fn シーン(self) -> パス別描画範囲 {
        self.シーン
    }

    pub fn シャドウ(self) -> パス別描画範囲 {
        self.シャドウ
    }

    pub(super) fn 終端(self) -> u32 {
        self.開始.saturating_add(self.個体数)
    }
}
