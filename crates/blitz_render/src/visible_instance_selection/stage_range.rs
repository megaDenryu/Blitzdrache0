//! 1つのLOD段が可視ID列の中に持つパスごとの区間。開始はその描画対象のID列の先頭からの相対位置である。
//! 列はパスの正典順(シーン→帯0から帯3)に区間を並べ、各パスの区間の内側を段番号の順に並べる。
//! したがって1つの段の区間は列の中で連続せず、パスごとに離れた5つの区間になる。段ごとに1つの連続範囲へ
//! まとめられないのは、1個体が複数の帯へ同時に所属しうるためである
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の帯別区間(4区分並べの後継)」)。
//!
//! 個体数はその段に属する個体の数であり、どのパスの描画数もこれを超えない。段別個体数の合計が描画対象の
//! 個体数と一致することが、どの段からも漏れた個体が無いことの根拠になる。

use super::pass_range::パス別描画範囲;
use super::visible_pass::{可視ID列を読むパス数, 可視パス};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 段別描画範囲 {
    個体数: u32,
    パス別: [パス別描画範囲; 可視ID列を読むパス数],
}

impl 段別描画範囲 {
    pub fn 生成する(個体数: u32, パス別: [パス別描画範囲; 可視ID列を読むパス数]) -> Self {
        Self { 個体数, パス別 }
    }

    /// 可視判定を持たない描画対象の段。どのパスもその段の全個体を描く。
    /// パスごとの区間を個体数ぶんずつずらして並べるのは、確保時の中身が恒等の列をパス数ぶん繰り返したものであり、
    /// この配置がそのまま正典順の区間の並びになるためである。列の位置は違ってもどのパスも同じ個体を同じ順で読む。
    /// 前提: 個体数とパス数の積がu32に収まる(可視ID列の容量が同じ積で確保されているため、破れれば確保が先に失敗する)。
    pub fn 全個体を描く(個体数: u32) -> Self {
        let 区間 = |添字: usize| {
            let 開始 = u32::try_from(添字)
                .ok()
                .and_then(|倍数| 倍数.checked_mul(個体数))
                .unwrap_or_else(|| panic!("パス数と個体数の積がu32に収まるという不変条件に違反した: 個体数{個体数}"));
            パス別描画範囲::生成する(開始, 個体数)
        };
        Self::生成する(個体数, std::array::from_fn(区間))
    }

    pub fn 個体数(self) -> u32 {
        self.個体数
    }

    pub fn パス(self, パス: 可視パス) -> パス別描画範囲 {
        self.パス別[パス.添字()]
    }
}
