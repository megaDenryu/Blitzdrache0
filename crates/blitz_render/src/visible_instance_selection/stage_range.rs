//! 1つのLOD段が可視ID列の中で占める範囲。開始はその描画対象のID列の先頭からの相対位置であり、
//! そのまま描画発行の先頭インスタンスになる。
//! 可視数と個体数を別に持つのは、シーンパスが範囲の先頭から可視数ぶんを、シャドウパスが同じ範囲の個体数ぶんを
//! 描くためである。並びの先頭側に可視個体を置くという規約が、この2つの数を同じ開始位置から使えることの根拠である。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「描画発行」

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 段別描画範囲 {
    開始: u32,
    可視数: u32,
    個体数: u32,
}

impl 段別描画範囲 {
    pub fn 生成する(開始: u32, 可視数: u32, 個体数: u32) -> Self {
        Self {
            開始, 可視数, 個体数
        }
    }

    pub fn 開始(self) -> u32 {
        self.開始
    }

    pub fn 可視数(self) -> u32 {
        self.可視数
    }

    pub fn 個体数(self) -> u32 {
        self.個体数
    }
}
