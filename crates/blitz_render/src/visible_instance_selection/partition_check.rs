//! 段の範囲が可視ID列を段番号の順に隙間なく重なりなく埋めていることと、段の内側が4区分の並びに従っていることの検査。
//! 受け取るのは1つの描画対象ぶんの段の範囲一覧とその対象のID列の長さ、返すのは受理か型付きエラーかである。
//! 段の範囲が重なるか隙間が空くと、一方のパスが他方の段の個体を描く。合計が列の長さに満たなければ、
//! どちらかのパスから漏れる個体が出る。
//! 4区分の整合を同じ場所で見るのは、段の範囲とその内側の2つのパス範囲が1つの並べ替えの結果であり、
//! 別々に検査すると「段は連続しているがパスの範囲が段の外を指す」組み合わせを取り逃がすためである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「描画発行」

use super::stage_range::段別描画範囲;
use super::可視ID列エラー;
use crate::error::レンダラーエラー;

#[cfg(test)]
mod partition_check_tests;

pub(super) fn 段範囲が列を隙間なく埋めるかを検査する(
    段範囲一覧: &[段別描画範囲],
    列の長さ: usize,
) -> Result<(), レンダラーエラー> {
    if 段範囲一覧.is_empty() {
        return Err(可視ID列エラー::段なし.into());
    }
    let mut 合計 = 0u32;
    for (段番号, 範囲) in 段範囲一覧.iter().enumerate() {
        if 範囲.開始() != 合計 {
            return Err(可視ID列エラー::段範囲が連続でない {
                段番号,
                開始: 範囲.開始(),
                期待: 合計,
            }
            .into());
        }
        四区分の並びを検査する(段番号, *範囲)?;
        合計 = 合計.saturating_add(範囲.個体数());
    }
    if usize::try_from(合計).is_ok_and(|値| 値 == 列の長さ) {
        return Ok(());
    }
    Err(可視ID列エラー::段別個体数の合計不一致 { 合計, 列の長さ }.into())
}

/// 段の内側が`[シーンのみ][両方][シャドウのみ][どちらも不可視]`の順に並んでいること。
/// シーンの範囲は先頭2区分、シャドウの範囲は中央2区分であるから、シーンは段の先頭から始まり、
/// シャドウはその内側で始まってシーンの終端以降まで伸び、どちらも段の終端を越えない。
fn 四区分の並びを検査する(段番号: usize, 範囲: 段別描画範囲) -> Result<(), レンダラーエラー> {
    let (シーン, シャドウ) = (範囲.シーン(), 範囲.シャドウ());
    if シーン.開始() != 範囲.開始() {
        return Err(可視ID列エラー::シーン範囲が段の先頭でない {
            段番号,
            シーン開始: シーン.開始(),
            段開始: 範囲.開始(),
        }
        .into());
    }
    if シーン.描画数() > 範囲.個体数() {
        return Err(可視ID列エラー::段の可視数超過 {
            段番号,
            可視数: シーン.描画数(),
            個体数: 範囲.個体数(),
        }
        .into());
    }
    if シャドウ.開始() < 範囲.開始() || シャドウ.開始() > シーン.終端() || シャドウ.終端() > 範囲.終端() {
        return Err(可視ID列エラー::シャドウ範囲が4区分に合わない {
            段番号,
            シャドウ開始: シャドウ.開始(),
            シャドウ終端: シャドウ.終端(),
            シーン終端: シーン.終端(),
            段開始: 範囲.開始(),
            段終端: 範囲.終端(),
        }
        .into());
    }
    Ok(())
}
