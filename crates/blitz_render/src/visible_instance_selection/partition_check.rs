//! 段の範囲が可視ID列を段番号の順に隙間なく重なりなく埋めていることの検査。受け取るのは1つの描画対象ぶんの
//! 段の範囲一覧とその対象のID列の長さ、返すのは受理か型付きエラーかである。
//! シーンパスとシャドウパスは同じ開始位置から違う件数を描くため、範囲が重なるか隙間が空くと一方のパスが
//! 他方の段の個体を描く。合計が列の長さに満たなければ、シャドウパスがどこかの個体を描かないことを意味する。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「描画発行」

use super::stage_range::段別描画範囲;
use super::可視ID列エラー;
use crate::error::レンダラーエラー;

/// 段の範囲が、可視ID列を段番号の順に隙間なく重なりなく埋めていることの検査。
/// 合計が列の長さに満たなければ、シャドウパスがどこかの個体を描かないことを意味する。
pub(super) fn 段範囲が列を隙間なく埋めるかを検査する(
    段範囲一覧: &[段別描画範囲],
    列の長さ: usize,
) -> Result<(), レンダラーエラー> {
    if 段範囲一覧.is_empty() {
        return Err(可視ID列エラー::段なし.into());
    }
    let mut 合計 = 0u32;
    for (段番号, 範囲) in 段範囲一覧.iter().enumerate() {
        if 範囲.開始() != 合計 {
            return Err(可視ID列エラー::段範囲が連続でない {
                段番号,
                開始: 範囲.開始(),
                期待: 合計,
            }
            .into());
        }
        if 範囲.可視数() > 範囲.個体数() {
            return Err(可視ID列エラー::段の可視数超過 {
                段番号,
                可視数: 範囲.可視数(),
                個体数: 範囲.個体数(),
            }
            .into());
        }
        合計 = 合計.saturating_add(範囲.個体数());
    }
    if usize::try_from(合計).is_ok_and(|値| 値 == 列の長さ) {
        return Ok(());
    }
    Err(可視ID列エラー::段別個体数の合計不一致 { 合計, 列の長さ }.into())
}
