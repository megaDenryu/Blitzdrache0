//! 選択の一覧と、その選択が指す可視ID列・段別描画範囲の本体。3つを1つの型にまとめるのは、
//! 区間が本体の内側に収まることとパス別の区間が列を隙間なく埋めることを生成の時点で確かめ、
//! 以降の引き当てが範囲外も重なりも持ち得ないようにするためである。

use super::interval_layout::パス区間が列を隙間なく埋めるかを検査する;
use super::selection::可視個体選択;
use super::stage_range::段別描画範囲;
use super::可視ID列エラー;
use crate::draw_bundle_id::描画束ID;
use crate::error::レンダラーエラー;

/// 1つの描画対象がそのフレームに描く個体の並びと、その並びの段ごとの切り分け。
#[derive(Clone, Copy)]
pub(crate) struct 個体描画計画<'a> {
    pub(crate) id列: &'a [u32],
    pub(crate) 段範囲一覧: &'a [段別描画範囲],
}

#[derive(Debug, Clone, Copy)]
pub struct 可視個体選択一覧<'a> {
    選択一覧: &'a [可視個体選択],
    id列: &'a [u32],
    段範囲列: &'a [段別描画範囲],
}

impl<'a> 可視個体選択一覧<'a> {
    pub fn 生成する(
        選択一覧: &'a [可視個体選択], id列: &'a [u32], 段範囲列: &'a [段別描画範囲]
    ) -> Result<Self, レンダラーエラー> {
        for 選択 in 選択一覧 {
            let 一覧 = Self {
                選択一覧, id列, 段範囲列
            };
            一覧.選択1件を検査する(*選択)?;
        }
        Ok(Self {
            選択一覧, id列, 段範囲列
        })
    }

    /// 該当する選択が無ければ`None`を返す。呼び出し元はそれを「この対象は可視判定と段選択の対象外であり、
    /// 全個体を最詳細段で描く」と読む。走査が線形なのは、選択の件数が常駐する群の数であり、
    /// 束ごとの描画対象数と同じ桁に収まるためである。
    pub(crate) fn 引く(&self, 束id: 描画束ID, 描画対象添字: usize) -> Option<個体描画計画<'a>> {
        let 選択 = self
            .選択一覧
            .iter()
            .find(|選択| 選択.束id() == 束id && 選択.描画対象添字() == 描画対象添字)?;
        Some(個体描画計画 {
            id列: self.id列.get(選択.id列開始()..選択.id列終端()?)?,
            段範囲一覧: self.段範囲列.get(選択.段範囲開始()..選択.段範囲終端()?)?,
        })
    }

    fn 選択1件を検査する(&self, 選択: 可視個体選択) -> Result<(), レンダラーエラー> {
        let Some(id列) = 選択.id列終端().and_then(|終端| self.id列.get(選択.id列開始()..終端)) else {
            return Err(可視ID列エラー::区間が範囲外 {
                開始: 選択.id列開始(),
                列の長さ: self.id列.len(),
            }
            .into());
        };
        let Some(段範囲一覧) = 選択.段範囲終端().and_then(|終端| self.段範囲列.get(選択.段範囲開始()..終端)) else {
            return Err(可視ID列エラー::段範囲区間が範囲外 {
                開始: 選択.段範囲開始(),
                列の長さ: self.段範囲列.len(),
            }
            .into());
        };
        パス区間が列を隙間なく埋めるかを検査する(段範囲一覧, id列.len())
    }
}
