//! 可視ID列の区間を持つパスと、その数え方。列はシーンパス用の区間と距離区分ごとのシャドウパス用の区間へ分かれ、
//! 同じ個体IDが距離区分をまたいで重複して現れる(キャスターの重複所属は正しい影に必要である)。
//! したがって1個体が列へ現れる回数はシーンと距離区分の合計が上限になり、容量の確保とメモリ見積はこの数を根拠にする。
//! 距離区分数から導く1箇所をここに置くのは、確保する側と見積る側が別々に4を書くと片方だけが古くなるためである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」

use crate::cascade::{距離区分数, 距離区分番号};

/// 1つの描画対象の可視ID列を読むパスの数。シーンパス1つと距離区分ごとのシャドウパス4つの合計である。
/// 1個体が列へ現れる回数はこの数が上限であり(シーンと全距離区分に可視な個体)、確保する容量は個体数のこの倍数になる。
pub const 可視ID列を読むパス数: usize = 1 + 距離区分数;

/// 可視ID列の中に自分の区間を持つパス。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 可視パス {
    シーン,
    影の距離区分(距離区分番号),
}

impl 可視パス {
    /// 列の中で区間が並ぶ順。確保・書き込み・区間の検査・描画発行のすべてがこの順を根拠にするため、
    /// 順序を持つのはこの1箇所だけである。
    pub fn 全パス() -> impl Iterator<Item = Self> {
        std::iter::once(Self::シーン).chain(距離区分番号::全距離区分().into_iter().map(Self::影の距離区分))
    }

    /// パス別の配列の添字。シーンが先頭で、続いて距離区分番号の順に並ぶ。
    pub fn 添字(self) -> usize {
        match self {
            Self::シーン => 0,
            Self::影の距離区分(番号) => 1 + 番号.添字(),
        }
    }

    /// 報告と型付きエラーの文面が使う名前。距離区分は`距離区分番号`のシャドウパス名と同じ綴りにして、
    /// GPU計器の区間名と計数の見出しが同じ語で並ぶようにする。
    pub fn 名前(self) -> &'static str {
        match self {
            Self::シーン => "シーン",
            Self::影の距離区分(番号) => 番号.シャドウパス名(),
        }
    }
}
