//! 1本の可視ID列を読むパスの数え方。列はシーンパス用の区間と帯ごとのシャドウパス用の区間へ分かれ、
//! 同じ個体IDが帯をまたいで重複して現れる(キャスターの重複所属は正しい影に必要である)。
//! したがって1個体が列へ現れる回数はシーンと帯の合計が上限になり、容量の確保とメモリ見積はこの数を根拠にする。
//! 帯数から導く1箇所をここに置くのは、確保する側と見積る側が別々に4を書くと片方だけが古くなるためである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の帯別区間(4区分並べの後継)」

use crate::cascade::帯数;

/// 1つの描画対象の可視ID列を読むパスの数。シーンパス1つと帯ごとのシャドウパス4つの合計である。
/// 1個体が列へ現れる回数はこの数が上限であり(シーンと全帯に可視な個体)、確保する容量は個体数のこの倍数になる。
pub(crate) const 可視ID列を読むパス数: usize = 1 + 帯数;
