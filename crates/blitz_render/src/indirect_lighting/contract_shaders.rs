//! 照明問い合わせ契約ごとに分かれた描画シェーダーの組。担うのは「束縛レイアウトの枝から、そのパイプラインが
//! 使う1組を選ぶ」ことだけであり、どちらを選ぶかの判断は持たない。
//!
//! 2つを1つの型で持つのは、片方だけが在る状態が意味を持たないためである。契約は起動時に決まるが、束を組み立てるのは
//! その手前の埋め込みシェーダーの読み出しであり、そこは契約を知らない。契約に応じて片方だけを読み込む形にすると、
//! 束の有無をもう1つの一致条件として突き合わせることになる。
//!
//! 頂点段は両方が同じものを持つ。頂点段が照明問い合わせのセットを1つも読まないため、契約で分ける理由が無い
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」)。
//!
//! 生成の入口が「共有頂点段1本と画素段2本」の3入力なのは、頂点段の共有を型で強制するためである。組み上がった
//! 2組の`シェーダー一式`を任意に受け取る形にすると、契約ごとに違う頂点段を渡せてしまい、共有が呼び出し側の規律に落ちる。

use crate::shader_set::{シェーダー一式, シェーダー一式エラー};
use crate::vulkan::pipeline_ledger::照明束縛レイアウト;

#[derive(Debug, Clone)]
pub struct 契約別の描画シェーダー {
    定数近似: シェーダー一式,
    遠方環境: シェーダー一式,
}

impl 契約別の描画シェーダー {
    /// 頂点段のバイト列を2組へ複製するのは、パイプラインの構築が組ごとにシェーダーモジュールを作るためである。
    /// 複製が起きるのは起動時の読み出しとホットリロードの差し替えのときだけであり、フレームごとの費用にならない。
    pub fn 生成する(
        共有頂点段: Vec<u8>, 定数近似の画素段: Vec<u8>, 遠方環境の画素段: Vec<u8>
    ) -> Result<Self, シェーダー一式エラー> {
        Ok(Self {
            定数近似: シェーダー一式::生成する(共有頂点段.clone(), 定数近似の画素段)?,
            遠方環境: シェーダー一式::生成する(共有頂点段, 遠方環境の画素段)?,
        })
    }

    pub(crate) fn 束縛レイアウトで選ぶ(&self, レイアウト: 照明束縛レイアウト) -> &シェーダー一式 {
        match レイアウト {
            照明束縛レイアウト::直接光と多段影 => &self.定数近似,
            照明束縛レイアウト::直接光と多段影と遠方環境 => &self.遠方環境,
        }
    }
}
