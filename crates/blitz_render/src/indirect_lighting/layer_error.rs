//! 間接照明の層の失敗を1つに畳んだ型。`レンダラーエラー`はこの1つを`#[from]`で受ける。
//!
//! 契約の不成立と1フレーム入力の不一致と検収の解析入力の不一致を1つの層の型へ束ねるのは、どれも
//! 「間接照明の供給元をどう扱うか」の対応が破れたことを表し、レンダラーの側から見れば同じ層の失敗だからである。
//! 空・布・多段と同じ畳み方である。破れた対応の中身は内側の3つの型が持ち、どの生存期間の不一致なのかは枝から読める。

use thiserror::Error;

use super::{間接照明入力不一致エラー, 間接照明契約エラー};
use crate::distant_environment::遠方環境の解析入力エラー;

#[derive(Debug, Clone, Copy, Error, PartialEq, Eq)]
pub enum 間接照明エラー {
    #[error("照明問い合わせ契約が要る資源を作れない: {0}")]
    契約不成立(#[from] 間接照明契約エラー),

    #[error("間接照明の1フレーム入力が資源と噛み合わない: {0}")]
    入力不一致(#[from] 間接照明入力不一致エラー),

    #[error("検収が注入する解析入力が資源と噛み合わない: {0}")]
    解析入力不一致(#[from] 遠方環境の解析入力エラー),
}
