//! 遠方環境の契約が1フレームに積む本数の見込み。担当するのは「鏡面の粗さ段数を受け取り、初回に焼くフレームと
//! 2回目以降に焼き直すフレームがそれぞれ積む本数を答える」ことである。
//!
//! 見込みを本番と同じ`焼き始めの記録`と`焼き上げの計画`から導くのは、検収が読む期待値を検収側で組み立てると、
//! 本番のレンダーグラフが誤った本数を積んでもその検収が通ってしまうためである。積む側と数える側に加えて
//! 期待する側も同じ1つの導出へ寄せる。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Ic-3bの実装」

use super::焼き始めの記録;
use crate::distant_environment::input::遠方環境の生成指示;
use crate::distant_environment::間接照明生成パス数;

/// 起動から定常までの2種類のフレームが積む本数。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 焼き上げ本数の見込み {
    /// まだ1度も焼いていない起動直後のフレーム。反射率積分表もこのフレームで1度だけ焼く。
    pub 初回に焼くフレーム: 間接照明生成パス数,
    /// 遠方環境キーが変わって焼き直すフレーム。反射率積分表は既に焼き終えているため含まない。
    pub 焼き直すフレーム: 間接照明生成パス数,
}

impl 焼き上げ本数の見込み {
    pub fn 導く(鏡面の粗さ段数: u32) -> Self {
        let mut 記録 = 焼き始めの記録::新規();
        let 初回 = 記録.計画を決める(遠方環境の生成指示::焼き直す, 鏡面の粗さ段数);
        let 二回目 = 記録.計画を決める(遠方環境の生成指示::焼き直す, 鏡面の粗さ段数);
        Self {
            初回に焼くフレーム: 初回.本数(),
            焼き直すフレーム: 二回目.本数(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 鏡面畳込みの既定の段数。
    const 段数: u32 = 6;

    #[test]
    fn 初回だけが反射率積分表を含み焼き直しはその1本ぶん少ない() {
        let 見込み = 焼き上げ本数の見込み::導く(段数);
        assert_eq!(見込み.初回に焼くフレーム.反射率積分表, 1);
        assert_eq!(見込み.焼き直すフレーム.反射率積分表, 0);
        assert_eq!(見込み.初回に焼くフレーム.合計(), 見込み.焼き直すフレーム.合計() + 1);
    }

    #[test]
    fn どちらのフレームも遠方環境と複製と拡散を各1本積む() {
        let 見込み = 焼き上げ本数の見込み::導く(段数);
        for 本数 in [見込み.初回に焼くフレーム, 見込み.焼き直すフレーム] {
            assert_eq!(本数.遠方環境, 1);
            assert_eq!(本数.最詳細段の複製, 1);
            assert_eq!(本数.拡散照度, 1);
            assert_eq!(本数.鏡面畳込み, 段数 - 1);
        }
    }
}
