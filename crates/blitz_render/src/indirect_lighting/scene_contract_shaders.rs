//! シーン描画の、照明問い合わせ契約ごとかつ材質変種ごとに分かれた描画シェーダーの組。担うのは「束縛レイアウトの枝から、
//! そのパイプラインが使う組を選ぶ」ことだけであり、どちらを選ぶかの判断は持たない。変種ごとの選び分けは`variant_stages`が持つ。
//!
//! 布の`契約別の描画シェーダー`と別の型なのは、布が材質変種を持たないためである。1つの型にすると、布の側が
//! 意味の無い2本目の画素段を用意することになる。
//!
//! 2つの契約を1つの型で持つのは、片方だけが在る状態が意味を持たないためである。契約は起動時に決まるが、束を組み立てるのは
//! その手前の埋め込みシェーダーの読み出しであり、そこは契約を知らない。契約に応じて片方だけを読み込む形にすると、
//! 束の有無をもう1つの一致条件として突き合わせることになる。
//!
//! 頂点段は4組すべてが同じものを持つ。頂点段が照明問い合わせのセットを1つも読まず、材質変種でも変わらないためである
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」)。
//!
//! 生成の入口が「共有頂点段1本と、契約と材質変種の組ごとの画素段」の形なのは、頂点段の共有を型で強制するためである。
//! 組み上がった`シェーダー一式`を任意に受け取る形にすると、組ごとに違う頂点段を渡せてしまい、共有が呼び出し側の規律に落ちる。
//!
//! 位置の不変装飾をここで付けるのは、シーンの頂点段がこの入口以外からエンジンへ入らないためである。埋め込みSPIR-Vの読み出しも
//! ホットリロードの再コンパイルもここを通るため、装飾の付いていない頂点段でパイプラインが作られる経路が構造として存在しなくなる
//! (参照: `crates/blitz_render/src/shader_set/position_invariant.rs`)。

mod variant_stages;

pub(crate) use variant_stages::材質変種別の画素段;

use crate::shader_set::{シェーダー一式エラー, 位置の不変装飾を付ける};
use crate::vulkan::pipeline_ledger::照明束縛レイアウト;

/// 契約と材質変種の組ごとの画素段のSPIR-V。4本を1つの値で受け取るのは、1本でも欠けた組で台帳を作れないためである。
pub struct 契約と材質変種ごとの画素段 {
    pub 定数近似の標準金属粗さpbr: Vec<u8>,
    pub 定数近似の地表の層の重ね合わせ: Vec<u8>,
    pub 遠方環境の標準金属粗さpbr: Vec<u8>,
    pub 遠方環境の地表の層の重ね合わせ: Vec<u8>,
}

#[derive(Debug, Clone)]
pub struct 契約別のシーン描画シェーダー {
    定数近似: 材質変種別の画素段,
    遠方環境: 材質変種別の画素段,
}

impl 契約別のシーン描画シェーダー {
    /// 頂点段のバイト列を各組へ複製するのは、パイプラインの構築が組ごとにシェーダーモジュールを作るためである。
    /// 複製が起きるのは起動時の読み出しとホットリロードの差し替えのときだけであり、フレームごとの費用にならない。
    pub fn 生成する(
        共有頂点段: Vec<u8>, 画素段: 契約と材質変種ごとの画素段
    ) -> Result<Self, シェーダー一式エラー> {
        let 装飾済み頂点段 = 位置の不変装飾を付ける(&共有頂点段)?;
        Ok(Self {
            定数近似: 材質変種別の画素段::生成する(
                &装飾済み頂点段,
                画素段.定数近似の標準金属粗さpbr,
                画素段.定数近似の地表の層の重ね合わせ,
            )?,
            遠方環境: 材質変種別の画素段::生成する(
                &装飾済み頂点段,
                画素段.遠方環境の標準金属粗さpbr,
                画素段.遠方環境の地表の層の重ね合わせ,
            )?,
        })
    }

    pub(crate) fn 束縛レイアウトで選ぶ(&self, レイアウト: 照明束縛レイアウト) -> &材質変種別の画素段 {
        match レイアウト {
            照明束縛レイアウト::直接光と多段影 => &self.定数近似,
            照明束縛レイアウト::直接光と多段影と遠方環境 => &self.遠方環境,
        }
    }
}
