//! 単一のシェーダー一式によるホットリロードを、その契約が受け付けないときの失敗。
//!
//! 契約の不成立や1フレーム入力の不一致と別に持つのは、破れた対応が違うためである。あちらは資源と入力の対応であり、
//! こちらは「差し替えようとしたシェーダーの組が、その契約の画素段の組と噛み合わない」という差し替え操作の対応である。
//!
//! 遠方環境の契約を拒む根拠は、画素段のエントリが契約ごとに分かれていることにある。旧来のホットリロードは
//! 監視先1本(既定は`shaders/scene.slang`)を頂点段と画素段の2エントリへコンパイルして1つの`シェーダー一式`を作り、
//! それを契約に関わらずシーンの全キーへ組み直す。遠方環境の契約でこれを通すと、定数近似の画素段が遠方環境の
//! パイプラインへ載る。レイアウトは上位互換であるため構築も束縛も成功してしまうが、遠方環境のヘッダは
//! 定数間接近似の係数の区画を0で残すため、差し替えた瞬間に間接光が無言で黒へ落ちる。
//!
//! 契約別のシェーダー束を丸ごと入れ替える差し替えは順3-Ic-3の前に別途入れる。それまでは受け付けないことを
//! 型で表し、無言の異契約差し替えを起こさない。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」

use thiserror::Error;

#[derive(Debug, Clone, Copy, Error, PartialEq, Eq)]
pub enum 間接照明のリロード拒否エラー {
    /// 遠方環境の契約で、単一のシェーダー一式による差し替えが要求された。
    #[error(
        "遠方環境の契約は単一のシェーダー一式では差し替えられない(定数近似の画素段が載ると間接光が黒へ落ちるため。契約別のシェーダー束の完全交換は順3-Ic-3の前に入れる)"
    )]
    遠方環境の契約は単一のシェーダー一式で差し替えられない,
}
