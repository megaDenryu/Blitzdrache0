//! そのフレームで何を焼くかの計画と、そこから決まる生成パスの本数の内訳。
//!
//! GPUのハンドルを1つも持たないのは、本番のレンダーグラフと、GPUを開かない検収の両方がこの1つの導出を通るためである。
//! 本数を別の場所で数え直すと、検収が通る式と本番が積む本数が別々に動きうる。積む側と数える側の正本をここに閉じる。

use crate::distant_environment::間接照明生成パス数;

/// 1フレームぶんの焼き上げの計画。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 焼き上げの計画 {
    遠方環境を焼く: bool,
    反射率積分表を焼く: bool,
    鏡面の粗さ段数: u32,
}

impl 焼き上げの計画 {
    /// 検収が解析入力を注入する実行の計画。3つの画像の中身は転送で埋まるため、生成パスを1本も積まない。
    /// 反射率積分表も焼かないのは、注入がその表も置き換えるためである。
    pub(crate) fn 何も焼かない(鏡面の粗さ段数: u32) -> Self {
        Self::組み立てる(false, false, 鏡面の粗さ段数)
    }

    /// 検収が遠方環境へ解析入力を注入する実行の計画。遠方環境の生成パスは転送へ差し替わるが、そこから導く
    /// 拡散照度と鏡面畳込みは生成側が焼くため、本数の内訳は焼いたフレームと同じである。
    /// 反射率積分表を焼かないのは、注入がその表も転送で置き換えるためである。
    pub(crate) fn 遠方環境から派生だけを焼く(鏡面の粗さ段数: u32) -> Self {
        Self::組み立てる(true, false, 鏡面の粗さ段数)
    }

    pub(super) fn 組み立てる(遠方環境を焼く: bool, 反射率積分表を焼く: bool, 鏡面の粗さ段数: u32) -> Self {
        Self {
            遠方環境を焼く,
            反射率積分表を焼く,
            鏡面の粗さ段数,
        }
    }

    /// 遠方環境と、そこから導く拡散照度・鏡面畳込みを焼き直すか。3つは同じ条件で一緒に焼き直す。
    pub fn 遠方環境を焼くか(self) -> bool {
        self.遠方環境を焼く
    }

    /// 反射率積分表を焼くか。大気にも時刻にも依らないため、起動後の1回だけ真になる。
    pub fn 反射率積分表を焼くか(self) -> bool {
        self.反射率積分表を焼く
    }

    /// 鏡面畳込みを計算で焼く段の数。最詳細段は遠方環境からの複製で作るため段数から1を引く。
    pub fn 計算で焼く鏡面の段数(self) -> u32 {
        self.鏡面の粗さ段数.saturating_sub(1)
    }

    /// この計画で積むパスの本数の内訳。レンダーグラフの積み上げが返す値もこの1つの導出から出る。
    pub fn 本数(self) -> 間接照明生成パス数 {
        if !self.遠方環境を焼く {
            return 間接照明生成パス数 {
                反射率積分表: u32::from(self.反射率積分表を焼く),
                ..間接照明生成パス数::焼かない()
            };
        }
        間接照明生成パス数::焼いたフレーム(self.計算で焼く鏡面の段数(), self.反射率積分表を焼く)
    }
}
