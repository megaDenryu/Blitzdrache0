//! 間接照明の1フレーム入力が、レンダラーが持つ遠方環境の照明資源と噛み合わないときの失敗。
//!
//! 契約の不成立と分けて持つのは、生存期間が違うためである。契約は起動時に1度だけ立ち、この不一致は
//! フレームごとに呼び出し元が渡す入力との対応で決まる。
//!
//! 空エラーへ入れないのは、遠方環境の契約が空段階を持たない起動でも成立するためである。空エラーは
//! 「空段階を持たない起動では起こらない」と自己定義しており、`--no-sky`でも通るこの工程の失敗とは相容れない。

use thiserror::Error;

#[derive(Debug, Clone, Copy, Error, PartialEq, Eq)]
pub enum 間接照明入力不一致エラー {
    /// 遠方環境の照明資源がある契約なのに、そのフレームの遠方環境の入力が渡されなかった。
    #[error("遠方環境の照明資源がある契約なのに遠方環境の入力が未指定")]
    遠方環境の入力なし,

    /// 遠方環境の照明資源を持たない契約なのに、そのフレームの遠方環境の入力が渡された。
    #[error("遠方環境の照明資源の無い契約に遠方環境の入力が指定された")]
    遠方環境の入力が余分,

    /// 遠方環境を焼く入力があるのに、焼く条件の正本である大気の入力が渡されなかった。
    /// 観測半径と太陽の天頂余弦を組めないため、既定値で焼かずにここで拒む。
    #[error("遠方環境を焼く入力があるのに大気媒体が未指定")]
    大気の入力なし,
}
