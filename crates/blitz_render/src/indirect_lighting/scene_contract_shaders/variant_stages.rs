//! 1つの照明問い合わせ契約の中で、材質変種ごとに分かれた画素段の組。担当するのは、変種の枝からその変種の
//! 画素段を選ぶことだけであり、どの契約に属するかは知らない。
//!
//! 変種ごとに画素段が分かれるのは、標準金属粗さPBRがベースカラー1枚からアルベドを読み、地表の層の重ね合わせが
//! 4層のタイルを重みで混ぜて作るためである。同じ照明式へ渡す入力の組み立てが相互排他に変わるため、
//! 実行時の分岐でなく別のシェーダーにする(参照: `_doc/設計/マルチマテリアルと材質境界.md`「材質の3軸」)。

use crate::shader_set::{シェーダー一式, シェーダー一式エラー};
use crate::vulkan::material_variant::材質変種キー;

#[derive(Debug, Clone)]
pub(crate) struct 材質変種別の画素段 {
    標準金属粗さpbr: シェーダー一式,
    地表の層の重ね合わせ: シェーダー一式,
}

impl 材質変種別の画素段 {
    pub(super) fn 生成する(
        装飾済み頂点段: &[u8],
        標準金属粗さpbrの画素段: Vec<u8>,
        地表の層の重ね合わせの画素段: Vec<u8>,
    ) -> Result<Self, シェーダー一式エラー> {
        Ok(Self {
            標準金属粗さpbr: シェーダー一式::生成する(装飾済み頂点段.to_vec(), 標準金属粗さpbrの画素段)?,
            地表の層の重ね合わせ: シェーダー一式::生成する(装飾済み頂点段.to_vec(), 地表の層の重ね合わせの画素段)?,
        })
    }

    pub(crate) fn 材質変種で選ぶ(&self, 変種: 材質変種キー) -> &シェーダー一式 {
        match 変種 {
            材質変種キー::標準金属粗さPBRの不透明両面 => &self.標準金属粗さpbr,
            材質変種キー::地表の層の重ね合わせの不透明両面 => &self.地表の層の重ね合わせ,
        }
    }
}
