//! まだ1度も焼いていない表現を覚えておく記録。触れる状態はこの2つの真偽値だけであり、他の資源へは触れない。
//! 呼び出し規律は「コマンドを記録して送信すると決めたフレームで1度だけ計画を求める」ことである。
//!
//! 上位層の指示は遠方環境キーの値の比較から導かれるため、鍵を記録した後にそのフレームが見送られた場合まで
//! 面倒を見られない。見送られたフレームの生成パスはGPUへ届かないため、格上げが無いと立方体画像は一度も
//! 書かれないまま「中身を保つ画像」として扱われ、内容が不定のまま間接照明に出る(大気のベイク済み画像と同じ地雷)。
//!
//! 反射率積分表を別の真偽値で持つのは、大気にも時刻にも依らず起動後の1回だけ焼くためである。

use super::焼き上げの計画;
use crate::distant_environment::input::遠方環境の生成指示;

/// 遠方環境と反射率積分表のそれぞれについて、まだ1度も焼いていないかを覚えておく。
pub struct 焼き始めの記録 {
    遠方環境を焼いたか: bool,
    反射率積分表を焼いたか: bool,
}

impl 焼き始めの記録 {
    pub fn 新規() -> Self {
        Self {
            遠方環境を焼いたか: false,
            反射率積分表を焼いたか: false,
        }
    }

    /// 指示を焼き始めまで格上げして計画を決め、焼くと決めた表現を焼いた側へ記録する。
    /// 鏡面の粗さ段数を受け取るのは、計画がそのまま積むパスの本数の内訳を答えるためである。
    pub fn 計画を決める(&mut self, 指示: 遠方環境の生成指示, 鏡面の粗さ段数: u32) -> 焼き上げの計画 {
        let 遠方環境を焼く = !self.遠方環境を焼いたか || 指示 == 遠方環境の生成指示::焼き直す;
        let 反射率積分表を焼く = !self.反射率積分表を焼いたか;
        self.遠方環境を焼いたか = self.遠方環境を焼いたか || 遠方環境を焼く;
        self.反射率積分表を焼いたか = true;
        焼き上げの計画::組み立てる(遠方環境を焼く, 反射率積分表を焼く, 鏡面の粗さ段数)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 鏡面畳込みの既定の段数。計画の本数の内訳がこの値から導かれる。
    const 段数: u32 = 6;

    #[test]
    fn まだ焼いていなければ前の結果を使う指示でも焼き直しへ格上げする() {
        let mut 記録 = 焼き始めの記録::新規();
        let 計画 = 記録.計画を決める(遠方環境の生成指示::前の結果を使う, 段数);
        assert!(計画.遠方環境を焼くか());
        assert!(計画.反射率積分表を焼くか());
    }

    #[test]
    fn 一度焼いた後は前の結果を使う指示で1本も積まない() {
        let mut 記録 = 焼き始めの記録::新規();
        記録.計画を決める(遠方環境の生成指示::焼き直す, 段数);
        let 計画 = 記録.計画を決める(遠方環境の生成指示::前の結果を使う, 段数);
        assert!(!計画.遠方環境を焼くか());
        assert!(!計画.反射率積分表を焼くか());
    }

    #[test]
    fn 一度焼いた後でも焼き直しの指示は遠方環境だけを焼き直す() {
        let mut 記録 = 焼き始めの記録::新規();
        記録.計画を決める(遠方環境の生成指示::焼き直す, 段数);
        let 計画 = 記録.計画を決める(遠方環境の生成指示::焼き直す, 段数);
        assert!(計画.遠方環境を焼くか());
        assert!(!計画.反射率積分表を焼くか());
    }
}
