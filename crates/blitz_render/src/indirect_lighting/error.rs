//! 世界方針から照明問い合わせ契約を構築する境界の失敗。契約が要る資源が揃っていないことだけを表す。
//!
//! 空エラーから分けて持つのは、空エラーが「空段階を持たない起動では起こらない」と自己定義しており、
//! 空を描かない世界でも成立すべき遠方環境の契約と矛盾するためである。実際、大気のベイク済み画像は
//! 空段階があるか契約が遠方環境であるかのどちらかで作られ、`--no-sky`でも遠方環境は成立する。
//!
//! レンダラー層のエラーから分けて持つのは、この失敗がGPUやドライバの不調ではなく、呼び出し元が選んだ契約と
//! 世界の方針の対応だけで決まるためである。無言で定数近似へ戻さないことが、この型が在る理由である。

use thiserror::Error;

#[derive(Debug, Clone, Copy, Error, PartialEq, Eq)]
pub enum 間接照明契約エラー {
    /// 遠方環境の契約を選んだが、大気の媒体そのものを持たない世界だった。
    /// 遠方環境はスカイビューのベイク済み画像を読んで焼くため、焼ける元が無い。
    #[error("天空の遠方環境の契約を選んだが、大気のベイク済み画像を焼けない構成である")]
    大気のベイク済み画像なし,
}
