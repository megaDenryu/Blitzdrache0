//! レンダラー1個につき1つ選ぶ、間接照明の供給元の契約。担当するのは「間接光をどの供給元が答えるかを型で決め、
//! その契約がどのGPU資源を要るかを答える」ことである。
//!
//! 枝を2つに閉じるのは、実在する供給元が定数近似と遠方環境の2つしか無いためである。2つ目の実在方式が来る前に
//! 汎用の合成器やGPU側の方式のタグを作らない(参照: `_doc/設計/放射輝度問い合わせ階層.md`「品質方式の初期の組(確定)」)。
//!
//! この型が失敗を返さないのは、契約が成立するかどうかが世界の側の事実(その世界が大気の媒体を持つか)で決まり、
//! レンダラーからは見えないためである。成立の判定は世界方針から契約を作る境界が持つ
//! (`blitz_engine`の`世界の間接照明方針::照明問い合わせ契約へ写す`)。
//!
//! 2つの判定を公開するのは、同じ条件をレンダラーの資源生成と呼び出し元の1フレーム入力の両方が要るためである。
//! 資源の有無とフレーム入力の有無は常に一致していなければならず、条件を2箇所で書くと片方だけが古くなって
//! 描画が型付きエラーで落ちる。正本をこの1箇所に閉じる。

/// 間接照明の供給元の契約。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 照明問い合わせ契約 {
    定数近似,           // 方向も位置も問わない定数間接近似だけで答える。遠方環境と派生表現の資源を1つも作らない
    遠方環境LambertGGX, // 遠方環境から焼いたLambert拡散照度とGGX鏡面畳込みで答える
}

impl 照明問い合わせ契約 {
    /// 遠方環境と派生表現のGPU資源を作るか。作ると答えるのは遠方環境の契約だけである。
    pub fn 遠方環境の資源を作るか(self) -> bool {
        match self {
            Self::定数近似 => false,
            Self::遠方環境LambertGGX => true,
        }
    }

    /// 大気のベイク済み画像の資源を作るか。空段階を持つ構成に加えて、遠方環境の契約でも作る。
    ///
    /// 空段階の有無だけを条件にしないのは、空背景の有無と表面への間接照明が独立だからである。屋内の世界も
    /// 空を描かない起動指定も、背景を止めるだけで間接照明の供給元を変えない。空を描かないまま遠方環境を焼く
    /// 経路がここで成立する(参照: `_doc/設計/放射輝度問い合わせ階層.md`「世界の間接照明方針と契約の2枝(3-Ic)」)。
    pub fn 大気のベイク済み画像を作るか(self, 空段階がある: bool) -> bool {
        空段階がある || self.遠方環境の資源を作るか()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 定数近似は遠方環境の資源を作らない() {
        assert!(!照明問い合わせ契約::定数近似.遠方環境の資源を作るか());
    }

    #[test]
    fn 遠方環境の契約は遠方環境の資源を作る() {
        assert!(照明問い合わせ契約::遠方環境LambertGGX.遠方環境の資源を作るか());
    }

    #[test]
    fn 定数近似の大気は空段階の有無だけで決まる() {
        assert!(照明問い合わせ契約::定数近似.大気のベイク済み画像を作るか(true));
        assert!(!照明問い合わせ契約::定数近似.大気のベイク済み画像を作るか(false));
    }

    #[test]
    fn 遠方環境の契約は空段階が無くても大気を作る() {
        assert!(照明問い合わせ契約::遠方環境LambertGGX.大気のベイク済み画像を作るか(false));
    }
}
