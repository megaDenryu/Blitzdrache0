//! レンダラーを生成するときに渡した素材とフレーム構成が噛み合わないときの失敗。
//!
//! フレーム入力の不一致から分けて持つのは、比べる相手が違うためである。あちらは毎フレーム渡される入力と
//! レンダラーが既に持っているものを突き合わせ、こちらは生成の1回だけ渡す素材と構成を突き合わせる。
//! 生存期間が違う2つを1つの型へ混ぜると、どちらの不一致なのかを型から読めなくなる。
//! `レンダラーエラー`へは`#[from]`で合流する。

use thiserror::Error;

use crate::frame_composition::フレーム段階;

#[derive(Debug, Clone, Copy, Error, PartialEq, Eq)]
pub enum 生成要求不一致エラー {
    /// 素材を渡したのに、その素材を実行する段階がフレーム構成に無かった。
    #[error("フレーム構成に必要な段階がないため素材を実行できない: {0:?}")]
    フレーム構成素材不一致(フレーム段階),

    /// 粒子シェーダーと粒子素材の有無が一致しなかった。片方だけの状態は呼び出し元の配線ミスである。
    #[error("粒子シェーダーと粒子素材の有無が一致しない")]
    粒子入力不一致,

    /// スキンメッシュ素材の属性数が、生成に渡した頂点数と一致しなかった(判断44)。
    #[error("スキン属性数{属性数}が頂点数{頂点数}と一致しない")]
    スキン属性数不一致 { 属性数: usize, 頂点数: usize },

    /// 動く個体の宣言が、描画シーン素材の持たない描画対象または個体を指していた。
    #[error("動く個体の宣言({描画対象添字}番目の描画対象の個体{個体添字})が描画シーン素材の範囲外である")]
    動く個体の宣言が素材の範囲外 { 描画対象添字: usize, 個体添字: u32 },
}
