//! 物理デバイスがエンジンの最低要件を満たさないときの失敗。
//! レンダラー層のエラーから分けて持つのは、ここに挙げる失敗が起動時のデバイス選定でだけ起こり、
//! どれも「この機材ではこのエンジンを動かせない」という同じ結論へ帰着するためである。`レンダラーエラー`へは`#[from]`で合流する。
//! 不足した機能の語彙を同じファイルへ置くのは、機能項目が失敗の内訳そのものであり、失敗を報告する以外の使い道が無いためである。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「ディスクリプタ索引の採用範囲」。

use thiserror::Error;

#[derive(Debug, Error)]
pub enum デバイス要件エラー {
    /// グラフィックス描画・提示、および必須機能(dynamicRendering・synchronization2・shaderDrawParameters)の両方に対応する物理デバイスが1つも見つからなかった。
    #[error(
        "グラフィックス表示・提示、および必須機能(dynamicRendering/synchronization2/shaderDrawParameters)に対応する物理デバイスが見つからなかった"
    )]
    適合物理デバイスなし,

    /// 材質テクスチャ表の索引化に要る機能が物理デバイスに無い。品質を落とした枝へ縮退させずここで失敗させるのは、
    /// この機能集合がシーンレンダラーの最低機能要件であり、同じ画素を出すための実装能力であって絵の品質の選択肢ではないためである。
    #[error("物理デバイスがディスクリプタ索引の最低機能要件を満たさない(不足: {})", 機能名を並べる(.0))]
    ディスクリプタ索引機能不足(Vec<ディスクリプタ索引機能項目>),
}

/// 索引化した材質テクスチャ表に要る機能のうちの1つ。Vulkanの綴りを返す名称を持たせるのは、
/// 読み手がエラーメッセージと機材のGPU情報を突き合わせられるようにするためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ディスクリプタ索引機能項目 {
    /// 長さがシェーダー側の宣言で固定されないディスクリプタ配列を使えること。
    実行時のディスクリプタ配列,
    /// 隣り合う画素が違う添字で画像ディスクリプタ配列を参照できること。
    非一様な添字での画像参照,
    /// 表の一部のスロットだけを書き込んだ状態で束縛できること。
    一部だけ書き込んだ表の束縛,
}

impl ディスクリプタ索引機能項目 {
    /// エンジンが最低要件とする3項目。照合も報告もこの順で並べる。
    pub const 全項目: [Self; 3] = [
        Self::実行時のディスクリプタ配列,
        Self::非一様な添字での画像参照,
        Self::一部だけ書き込んだ表の束縛,
    ];

    /// Vulkanの機能フラグの綴り。
    pub fn 機能名(self) -> &'static str {
        match self {
            Self::実行時のディスクリプタ配列 => "runtimeDescriptorArray",
            Self::非一様な添字での画像参照 => "shaderSampledImageArrayNonUniformIndexing",
            Self::一部だけ書き込んだ表の束縛 => "descriptorBindingPartiallyBound",
        }
    }
}

fn 機能名を並べる(項目一覧: &[ディスクリプタ索引機能項目]) -> String {
    項目一覧.iter().map(|項目| 項目.機能名()).collect::<Vec<_>>().join(", ")
}
