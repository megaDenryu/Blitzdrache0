//! 1フレーム分の入力が、レンダラーが保持するフレーム構成・提示先・描画対象資源と噛み合わないときの失敗。
//! レンダラー層のエラーから分けて持つのは、ここに挙げる失敗がGPUやドライバの不調ではなく、呼び出し元が渡したそのフレームの入力と
//! レンダラーが既に持っているものの対応だけで決まるためである。布・空と同じく、層ごとに型を分けてどの層が何を拒むのかを読めるようにする。
//! `レンダラーエラー`へは`#[from]`で合流する。

use thiserror::Error;

use crate::draw_bundle_id::描画束ID;

#[derive(Debug, Error)]
pub enum フレーム入力不一致エラー {
    #[error("現在の提示先は単一視点だけを描画できるが、フレーム入力に{視点数}視点が指定された")]
    複数視点提示未対応 { 視点数: usize },

    #[error("読み戻し要求に必要な読み戻し段階がフレーム構成に含まれていない")]
    読み戻し段階なし,

    /// ポスト処理を持たない構成はシーンが直接スワップチェーンへ描くため、明るさの圧縮前のHDR中間画像そのものが存在しない。
    #[error("圧縮前のHDRの読み戻しを要求されたが、フレーム構成にポスト処理の段階が含まれていない")]
    圧縮前のHDRの読み戻しにポスト処理が要る,

    /// プリミティブ描画発行一覧が、レンダラーの保持する描画対象の並びを持っていなかった。
    /// 描くインデックス区間を決められないため、無言で対象を飛ばさずに失敗させる。
    #[error("束{束id:?}の{描画対象添字}番目の描画対象にプリミティブ描画発行が1件も無い")]
    プリミティブ発行不在 { 束id: 描画束ID, 描画対象添字: usize },

    /// 検収が与えた合成深度の画素数が、そのときのスワップチェーンの画素数と違っていた。
    /// 寸法を合わせずに転送すると画像の一部だけが書き換わり、残りの画素は深度プリパスが書いた本番の深度のまま残る。
    /// その状態で読み戻した局所可視度は合成の形とも本番の形とも一致せず、写しの誤りと切り分けられない。
    #[error("注入する合成深度が幅{与えた幅}高さ{与えた高さ}で、画面の幅{画面の幅}高さ{画面の高さ}と違う")]
    合成深度の寸法不一致 {
        与えた幅: u32,
        与えた高さ: u32,
        画面の幅: u32,
        画面の高さ: u32,
    },

    /// 検収が与えた時間再構成の合成入力の成分の数が、寸法から決まる数と違っていた。
    /// 短い側で転送を打ち切ると画像の一部だけが書き換わり、残りの画素は本番の描画結果のままCPU正本と突き合わされる。
    #[error("注入する時間再構成の合成入力の{項目}が{与えた}要素で、寸法から決まる{期待}要素と違う")]
    合成入力の要素数不一致 { 項目: &'static str, 与えた: usize, 期待: usize },

    /// 検収が与えた時間再構成の合成入力の画素数が、そのときのスワップチェーンの画素数と違っていた。
    /// 合成深度の寸法不一致と同じ理由で、寸法を合わせずに転送すると画像の一部だけが書き換わる。
    #[error("注入する時間再構成の合成入力が幅{与えた幅}高さ{与えた高さ}で、画面の幅{画面の幅}高さ{画面の高さ}と違う")]
    合成入力の寸法不一致 {
        与えた幅: u32,
        与えた高さ: u32,
        画面の幅: u32,
        画面の高さ: u32,
    },

    /// 動く個体を1体も宣言していない描画対象へ、そのフレームの位置指定が来た。読込時に静的な個体変換だけを確保しており
    /// 毎フレームの書き込み先が無いため、供給を無言で捨てずに失敗させる。
    #[error("動く個体を宣言していない描画対象へ個体{個体添字}の位置指定が来た")]
    動く個体を持たない描画対象への位置指定 { 個体添字: u32 },

    /// 動く個体を持つ描画対象へ、宣言していない個体の位置指定が来た。宣言した個体だけが読込時の内容を保持しており、
    /// 向きと寸法を保ったまま位置を差し替える材料が無い。
    #[error("動く個体として宣言されていない個体{個体添字}への位置指定が来た")]
    動く個体として宣言されていない個体への位置指定 { 個体添字: u32 },

    /// 動く個体の位置がその描画対象の描画の基準原点からf32で表せる範囲を外れた。
    #[error("動く個体の位置を描画の基準原点からの相対へ狭められない: {0}")]
    動く個体の位置が基準原点から遠すぎる(blitz_math::座標変換エラー),

    /// プリミティブ描画発行が指す材質スロット番号の資源を、その描画対象が持っていなかった。
    /// 無言で他の材質を束ねると、材質境界が消えたまま絵が成立する。
    #[error("束の{描画対象添字}番目の描画対象が材質スロット番号{スロット番号}の資源を持たない")]
    材質スロット未確保 { 描画対象添字: usize, スロット番号: u32 },
}
