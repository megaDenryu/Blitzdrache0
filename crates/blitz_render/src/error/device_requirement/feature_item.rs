//! 索引化した材質テクスチャ表に要る機能の語彙。エンジンが最低要件とする2項目と、その綴りを所有する。
//! 参照: `_doc/計画/ユビキタス言語.md`「データの語彙」のディスクリプタ索引機能項目。

/// 索引化した材質テクスチャ表に要る機能のうちの1つ。Vulkanの綴りを返す名称を持たせるのは、
/// 読み手がエラーメッセージと機材のGPU情報を突き合わせられるようにするためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ディスクリプタ索引機能項目 {
    /// 隣り合う画素が違う添字で画像ディスクリプタ配列を参照できること。
    非一様な添字での画像参照,
    /// 表の一部のスロットだけを書き込んだ状態で束縛できること。
    一部だけ書き込んだ表の束縛,
}

impl ディスクリプタ索引機能項目 {
    /// エンジンが最低要件とする2項目。照合も報告もこの順で並べる。
    /// 注意: シェーダーが材質テクスチャ表を要素数固定の配列で宣言する限り`runtimeDescriptorArray`は要らない。
    /// 要素数を書かない配列へ戻すときに再び足す(参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「ディスクリプタ索引の採用範囲」)。
    pub const 全項目: [Self; 2] = [Self::非一様な添字での画像参照, Self::一部だけ書き込んだ表の束縛];

    /// Vulkanの機能フラグの綴り。
    pub fn 機能名(self) -> &'static str {
        match self {
            Self::非一様な添字での画像参照 => "shaderSampledImageArrayNonUniformIndexing",
            Self::一部だけ書き込んだ表の束縛 => "descriptorBindingPartiallyBound",
        }
    }
}
