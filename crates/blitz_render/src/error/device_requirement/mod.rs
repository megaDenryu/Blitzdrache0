//! 物理デバイスがエンジンの最低要件を満たさないときの失敗。
//! レンダラー層のエラーから分けて持つのは、ここに挙げる失敗が起動時のデバイス選定でだけ起こり、
//! どれも「この機材ではこのエンジンを動かせない」という同じ結論へ帰着するためである。`レンダラーエラー`へは`#[from]`で合流する。
//! 要求する機能の語彙は`feature_item`、機材1件ぶんの不足内訳は`shortfall`が持つ。
//! 不足内訳の型を`error`の再輸出へ載せないのは、組み立てる選定と読むエラー表示以外に使い道が無く、
//! 層の入口の名前を増やす価値が無いためである。使う側はモジュール経由で参照する。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「ディスクリプタ索引の採用範囲」。

mod feature_item;
mod shortfall;

pub use feature_item::ディスクリプタ索引機能項目;
pub use shortfall::機材別のディスクリプタ索引機能不足;

use thiserror::Error;

/// 物理デバイスの選定が満たすべき要件を段階的に絞り込み、どの段で落ちたかを表す列挙。
///
/// `適合物理デバイスなし`は、グラフィックス描画・提示、および必須機能(dynamicRendering・synchronization2・
/// shaderDrawParameters)の両方に対応する物理デバイスが1つも見つからなかった場合。
///
/// `ディスクリプタ索引機能不足`は、基礎要件を満たす候補はあったがそのどれもが材質テクスチャ表の索引化に要る
/// 機能を欠いた場合。品質を落とした枝へ縮退させずここで失敗させるのは、この機能集合がシーンレンダラーの
/// 最低機能要件であり、同じ画素を出すための実装能力であって絵の品質の選択肢ではないためである。候補ごとに
/// 並べるのは、複数のGPUを積んだ機材でどのGPUが何を欠いたのかを1件の内訳では表せないためである。
///
/// `テクスチャのブロック圧縮非対応`は、索引の機能まで満たす候補はあったがそのどれもがテクスチャのブロック
/// 圧縮に対応しなかった場合。非圧縮の版を同時に焼いて機材に選ばせる枝も、実行時にCPUで展開して非圧縮として
/// 載せる枝も持たないため、ここで失敗させる(参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`
/// 「判断e」)。欠ける機能が1つしかないため、機材名だけを並べる。
///
/// `立方体の配列画像非対応`は、ブロック圧縮まで満たす候補はあったがそのどれもが立方体の配列画像に対応しな
/// かった場合。点光源の影が1枚の立方体配列を標本する形に固まっており、面ごとの2D配列として引き直す枝を
/// 持たないため、ここで失敗させる(参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断l」)。欠ける機能が
/// 1つしかないため、機材名だけを並べる。
#[derive(Debug, Error)]
pub enum デバイス要件エラー {
    #[error(
        "グラフィックス表示・提示、および必須機能(dynamicRendering/synchronization2/shaderDrawParameters)に対応する物理デバイスが見つからなかった"
    )]
    適合物理デバイスなし,
    #[error("ディスクリプタ索引の最低機能要件を満たす物理デバイスが無い: {}", 機材別に並べる(.0))]
    ディスクリプタ索引機能不足(Vec<機材別のディスクリプタ索引機能不足>),
    #[error("テクスチャのブロック圧縮(textureCompressionBC)に対応する物理デバイスが無い: {}", .0.join(" / "))]
    テクスチャのブロック圧縮非対応(Vec<String>),
    #[error("立方体の配列画像(imageCubeArray)に対応する物理デバイスが無い: {}", .0.join(" / "))]
    立方体の配列画像非対応(Vec<String>),
}

fn 機材別に並べる(不足内訳一覧: &[機材別のディスクリプタ索引機能不足]) -> String {
    不足内訳一覧.iter().map(ToString::to_string).collect::<Vec<_>>().join(" / ")
}
