//! 索引化した材質テクスチャ表の台帳と世代で起こる失敗。担当するのは、旧スロット別セット経路では起こりえない失敗を
//! 1つの層へ集め、レンダラーエラーの1バリアントへ畳むことである。
//!
//! 注意: レイアウト容量の超過はディスクリプタを1つも作る前に返す。作った後に判定すると、容量を超えた表への書込が
//! validation layerの指摘として先に出て、原因の材質数へ辿り着けない。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「未決定の事項」

use thiserror::Error;

use crate::vulkan::material_variant::材質能力エラー;

#[derive(Debug, Error, Clone, PartialEq)]
pub enum 材質資源表エラー {
    /// 材質の3軸が、このエンジンが描けると宣言した組合せの外にあった。材質変種キーの導出が判定する。
    #[error("材質の3軸をこのエンジンが描けない: {0}")]
    材質能力不足(#[from] 材質能力エラー),

    #[error("同じ大域材質ID{材質id}が1つの資源表世代へ2回現れた")]
    材質IDの重複 { 材質id: u64 },

    #[error("大域材質ID{材質id}はこの資源表世代に無い")]
    未知の材質ID { 材質id: u64 },

    #[error("テクスチャID{テクスチャid}が別の画像またはビュー契約で2回現れた")]
    テクスチャIDの衝突 { テクスチャid: u64 },

    #[error("資源表世代が常駐させる{常駐枚数}枚が、材質テクスチャ表のレイアウト容量{レイアウト容量}枚を超えた")]
    レイアウト容量超過 { 常駐枚数: u32, レイアウト容量: u32 },

    #[error("テクスチャスロットの発番数{発番数}が、この世代の常駐枚数の見積{見積枚数}を超えた")]
    常駐枚数の見積不足 { 発番数: u32, 見積枚数: u32 },

    #[error("画素段の予約枠{予約枚数}がデバイス上限{上限}以上であり、材質テクスチャ表へ割ける枚数が残らない")]
    予算不足 { 予約枚数: u32, 上限: u32 },

    #[error("資源表世代の番号が上限に達したため、新しい世代を公開できない")]
    世代番号の枯渇,

    #[error("材質GPU参照の世代{参照の世代}が、束縛する資源表世代{束縛する世代}と一致しない")]
    異世代の混在 { 参照の世代: u32, 束縛する世代: u32 },

    #[error("材質{材質id}の特徴ビットとテクスチャスロットが食い違う")]
    特徴ビットとスロットの不整合 { 材質id: u64 },

    #[error("材質{材質id}のテクスチャスロット{スロット}が、この世代の画像{画像枚数}枚の範囲外を指す")]
    スロットが範囲外 { 材質id: u64, スロット: u32, 画像枚数: u32 },

    #[error("材質{材質id}の係数{係数}が0以上1以下の有限値でない")]
    係数の範囲外 { 材質id: u64, 係数: f32 },
}
