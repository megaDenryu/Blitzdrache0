//! 材質描画族のパイプライン台帳で起こる失敗。担当するのは、キーと台帳の食い違いを、
//! Vulkanの生成失敗とは別の層の失敗として区別することである。
//!
//! どの枝も呼び出し側の組み立ての誤りであり、GPUの資源不足ではない。分けておくと、起動が落ちたときに
//! 「機材が足りない」と「必要キー集合の数え上げを誤った」を取り違えずに済む。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段6

use thiserror::Error;

#[derive(Debug, Error, Clone, PartialEq, Eq)]
pub enum パイプライン台帳エラー {
    #[error("パイプラインキー{記述}は台帳に無い(起動時の必要キー集合の数え上げが足りていない)")]
    未知のキー { 記述: String },

    #[error("パイプラインキー{記述}が必要キー集合に2回現れた")]
    キーの重複 { 記述: String },

    #[error("シーンのパイプラインキー{記述}の描画先が色の添付を持たない")]
    色の無い描画先でシーンを描く { 記述: String },

    #[error("{族}のシェーダーを持つ供給元へ、別の族のパイプラインキー{記述}を渡した")]
    族とキーの不一致 { 族: &'static str, 記述: String },
}
