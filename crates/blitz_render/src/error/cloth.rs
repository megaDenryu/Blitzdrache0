//! 布(判断52〜54)の生成・毎フレーム入力・描画で起こりうる失敗。
//! レンダラー層のエラーから分けて持つのは、ここに挙げる失敗が布を持たない起動では1つも起こらず、
//! どれも布の資源と布へ渡す入力の対応が取れていないことに帰着するためである。`レンダラーエラー`へは`#[from]`で合流する。

use thiserror::Error;

use crate::cloth_material::スキン頂点添字;

#[derive(Debug, Error)]
pub enum 布エラー {
    #[error("布介入が不正だった(上限超過またはバイト長不整合): 件数{件数}, バイト長{バイト長}")]
    介入不正 { 件数: u32, バイト長: usize }, // 布介入(掴み・離し)のバイト列が上限件数またはバイト長の契約を破った(判断53)

    #[error("布フレーム入力と布資源の有無が一致しない: {0}")]
    入力不一致(String), // 布資源の有無とフレーム描画入力の布の有無が食い違った(判断54)

    #[error("布の目標の更新対応のスキン頂点添字{添字}が頂点数{頂点数}の範囲外だった")]
    アタッチ先範囲外 { 添字: スキン頂点添字, 頂点数: u32 }, // 布の動く目標に指定されたスキン頂点の添字が頂点数の外を指した(判断52)

    #[error("動く目標を持つ布はスキン付きシーンでのみ使える(スキニング資源が無い)")]
    スキン必須, // 動く目標を持つ布はスキン付きシーン(スキン済み頂点バッファ)を前提とする(判断52の合流点)

    #[error("布が1描画で進める刻み数{本数}が上限{上限}を超えた")]
    刻み数超過 { 本数: u32, 上限: u32 }, // 1フレームのパス数の上限がこの刻み数から決まるため、越えた本数は受け取らない
}
