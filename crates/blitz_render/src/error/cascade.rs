//! 多段シャドウの構築にまつわる失敗。方向光の影を持たない構成でも多段は毎フレーム組み立てるが、
//! 失敗の理由は「カメラ視錐台と正射影の値」と「設定と資源の食い違い」の2つに限られるため、層を分けてここが持つ。

use thiserror::Error;

use crate::lighting_input::ライティング入力エラー;

#[derive(Debug, Error)]
pub enum 多段エラー {
    #[error("多段の組み立てが失敗した(カメラ視錐台の退化・正射影の値の不正): {0}")]
    構築失敗(#[from] ライティング入力エラー),

    /// 多段の設定が持つシャドウマップの一辺が、実際に確保したシャドウマップ資源の一辺と食い違った。
    /// ずれるとテクセルスナップの刻みが実際のテクセルの幅と合わずに静止物の影が泳ぎ、
    /// 世界メートル毎テクセルの報告値も実物と違う値になるため、描く前に失敗させる。
    #[error("多段設定のシャドウマップ一辺{設定}が確保済み資源の一辺{資源}と一致しない")]
    一辺解像度不一致 { 設定: u32, 資源: u32 },
}
