//! 空パスと、空段階が所有する大気のベイク済み画像にまつわる失敗。空段階を持たない起動では起こらないため、
//! 層を分けてここが持つ。

use thiserror::Error;

use crate::frame_input::空入力エラー;

/// 空パス資源の有無とフレーム描画入力の空の有無が噛み合わないときの失敗。
///
/// `入力不一致`は空パス資源の有無とフレーム描画入力の空の有無が一致しなかった場合。無言で空を描かない
/// ことも、無言で既定の空を描くこともしない。`逆行列が非有限`は空パスが視線の向きを復元するために使う、
/// ビュー射影の逆行列が有限にならなかった場合。
#[derive(Debug, Error)]
pub enum 空エラー {
    #[error("空入力と空パス資源の有無が一致しない: {0}")]
    入力不一致(String),
    #[error("ビュー射影行列の逆行列が有限でない")]
    逆行列が非有限,
    #[error("空入力の値が不変条件を破った: {0}")]
    入力不正(#[from] 空入力エラー),
}
