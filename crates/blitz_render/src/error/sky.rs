//! 空パスと、空段階が所有する大気のベイク済み画像にまつわる失敗。空段階を持たない起動では起こらないため、
//! 層を分けてここが持つ。ベイク済み画像を読んで焼く遠方環境の契約の不成立もここへ入れるのは、
//! 欠けている資源がベイク済み画像そのものであり、拒む理由が空段階の有無だけで決まるためである。

use thiserror::Error;

use crate::frame_input::空入力エラー;

#[derive(Debug, Error)]
pub enum 空エラー {
    /// 空パス資源の有無とフレーム描画入力の空の有無が一致しなかった。
    /// 無言で空を描かないことも、無言で既定の空を描くこともしない。
    #[error("空入力と空パス資源の有無が一致しない: {0}")]
    入力不一致(String),

    /// 空パスが視線の向きを復元するために使う、ビュー射影の逆行列が有限にならなかった。
    #[error("ビュー射影行列の逆行列が有限でない")]
    逆行列が非有限,

    #[error("空入力の値が不変条件を破った: {0}")]
    入力不正(#[from] 空入力エラー),

    /// 天空の遠方環境の契約を選んだが、大気のベイク済み画像を作らないフレーム構成だった。
    /// 焼ける元が無いため、定数近似へは戻さずここで拒む。
    #[error("天空の遠方環境の契約を選んだが、大気のベイク済み画像を作らないフレーム構成である")]
    遠方環境の元になる大気がない,
}
