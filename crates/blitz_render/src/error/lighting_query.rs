//! 照明問い合わせ資源の内容の組み立てと梱包で起こりうる失敗。担当するのは、ヘッダの件数と実レコード列が
//! 食い違う失敗と、存在しない影の資源を指す可視性の失敗と、ヘッダが運ぶクラスタ写像の材料が値域を外れた失敗を
//! 表すことである。
//!
//! ディスクリプタへ書く前にここで落とすのは、件数が実体より多いとシェーダーが書き込まれていない領域を読み、
//! 件数が実体より少ないと書いたはずの光が黙って1つ消えるためである。無言の切り下げも切り上げもしない。
//!
//! `Eq`を持たないのは、クラスタ多光源の入力エラーが拒んだ値を実数のまま載せるためである。

use thiserror::Error;

use crate::clustered_lighting::クラスタ多光源入力エラー;

#[derive(Debug, Clone, Copy, Error, PartialEq)]
pub enum 照明問い合わせ梱包エラー {
    #[error("方向光のヘッダ件数{件数}が実レコード数{レコード数}と一致しないか、容量{容量}を超えている")]
    方向光の件数不整合 { 件数: u32, レコード数: usize, 容量: usize },
    #[error("局所光のヘッダ件数{件数}が実レコード数{レコード数}と一致しないか、容量{容量}を超えている")]
    局所光の件数不整合 { 件数: u32, レコード数: usize, 容量: usize },
    #[error("局所光レコードの並びへ{件数}件目を積もうとしたが、容量は{容量}件である")]
    局所光レコードが容量を超えた { 件数: usize, 容量: usize },
    #[error("方向光の可視性が指す多段影の資源添字{資源添字}が、現行の影資源の組数{組数}の範囲外である")]
    多段影の資源添字が範囲外 { 資源添字: u32, 組数: u32 },
    #[error("照明問い合わせヘッダが運ぶクラスタ写像の材料が値域を外れた: {0}")]
    クラスタ写像の材料が値域外(#[from] クラスタ多光源入力エラー),
}
