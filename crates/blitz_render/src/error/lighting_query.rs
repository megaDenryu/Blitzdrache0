//! 照明問い合わせ資源の梱包で起こりうる失敗。担当するのは「ヘッダの件数と実レコード数と容量が整合しない」
//! 1種類の失敗を、光の種類ごとに主語を分けて表すことである。
//!
//! ディスクリプタへ書く前にここで落とすのは、件数がレコード数を超えるとシェーダーが書き込まれていない領域を
//! 読むためである。無言で件数を切り下げると、光が1つ消えた絵を正常として出してしまう。

use thiserror::Error;

#[derive(Debug, Clone, Copy, Error, PartialEq, Eq)]
pub enum 照明問い合わせ梱包エラー {
    #[error("方向光のヘッダ件数{件数}が実レコード数{レコード数}または容量{容量}と整合しない")]
    方向光の件数不整合 { 件数: u32, レコード数: usize, 容量: usize },
    #[error("局所光のヘッダ件数{件数}が実レコード数{レコード数}または容量{容量}と整合しない")]
    局所光の件数不整合 { 件数: u32, レコード数: usize, 容量: usize },
}
