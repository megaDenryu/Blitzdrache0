//! レンダラーの生成・描画・破棄で起こりうる失敗を1つに畳んだ層のエラー型。担当するのは、層ごとのエラーと
//! Vulkanの失敗コードを呼び出し元へ`?`で伝播できる1つの型に束ねることである。
//!
//! 注意: `From<ash::LoadingError>` / `From<ash::vk::Result>` はash型を「受け取って自前表現へ変換する」だけであり、公開APIからash型を取り出せる経路にはならない。バリアント自体は自前表現(String・Vulkan失敗コード)のみを保持する。

use thiserror::Error;

use super::{cascade, cloth, device_requirement, frame_input_mismatch, generate_request, lighting_query, material_table, pipeline_ledger, sky};
use crate::indirect_lighting;
use crate::vulkan_failure::Vulkan失敗コード;

/// レンダラーの生成・描画・破棄で起こりうる失敗を層ごとに束ねた列挙。
///
/// `デバイス要件不足`・`テクスチャ形式不正`・`布不正`・`材質資源表不正`・`多段不正`・`照明問い合わせ梱包不正`・
/// `パイプライン台帳不正`・`間接照明不正`・`生成要求不一致`・`局所可視性不正`・`フレーム入力不一致`・`空不正`・
/// `可視ID列不正`は`#[from]`で層ごとの詳細なエラー型を包んでおり、原因の詳細はそれぞれの型が持つ。
///
/// `サーフェス形式なし`・`ホスト可視メモリ型なし`・`デバイスローカルメモリ型なし`はVulkan仕様上は到達しない
/// はずの経路だが、外部デバイス由来のため型では防ぎきれず用意している。
///
/// 注意: `SPIRV読み込み失敗`は`シェーダー一式`が4バイト整列を検証済みのため、ここに到達するのはslangcが
/// 不正なSPIR-Vを出力した場合のみである。
///
/// 参照: `読み戻し非対応`は判断9(ほぼ全環境で対応するが、非対応環境では通常描画のみ可能)。
/// `スキン行列不一致`は判断44であり、無言のデフォルト姿勢適用はしない(CLAUDE.md「不在・未設定・使用不可」)。
#[derive(Debug, Error)]
pub enum レンダラーエラー {
    #[error("Vulkanローダーの読み込みに失敗した: {0}")]
    ローダー読み込み失敗(String), // vulkan-1.dllの動的読み込みに失敗した
    #[error("Vulkan呼び出しが失敗した: {0}")]
    Vulkan呼び出し失敗(Vulkan失敗コード), // Vulkan API呼び出しがエラーコードを返した
    #[error("物理デバイスがエンジンの最低要件を満たさない: {0}")]
    デバイス要件不足(#[from] device_requirement::デバイス要件エラー), // 適合デバイスなし・必要機能不足
    #[error("サーフェスが提示形式を1つも報告しなかった")]
    サーフェス形式なし,
    #[error("SPIR-Vバイト列の読み込みに失敗した: {0}")]
    SPIRV読み込み失敗(String),
    #[error("ホスト可視かつコヒーレントなメモリ型が見つからなかった")]
    ホスト可視メモリ型なし, // 読み戻しバッファの確保に必要
    #[error("サーフェスがTRANSFER_SRC用途をサポートしないため読み戻せない")]
    読み戻し非対応,
    #[error("デバイスローカルなメモリ型が見つからなかった")]
    デバイスローカルメモリ型なし, // 深度バッファの確保に必要
    #[error("テクスチャの格納形式をこの経路では載せられない: {0}")]
    テクスチャ形式不正(#[from] super::texture_format::テクスチャ形式エラー),
    #[error("スキン行列とスキンメッシュの有無が一致しない: {0}")]
    スキン行列不一致(String),
    #[error("スキン付きシーンのシーン差し替えは未対応")]
    スキン付きシーン差し替え未対応, // M8最小実装の制約
    #[error("布の入力が不正である: {0}")]
    布不正(#[from] cloth::布エラー), // 判断52〜54、布を持たない起動では起こらない
    #[error("描画対象のローカルからワールドへの変換が逆行列を持たない")]
    描画対象変換非可逆,
    #[error("描画対象の個体数{0}がu32に収まらない")]
    個体数過大(usize), // 1つの描画対象が持つ個体数がGPUの描画発行で表せる範囲を超えた
    #[error("プリミティブのインデックス区間または頂点基準の値{0}が描画発行の幅に収まらない")]
    プリミティブ区間過大(u64),
    #[error("可視ID列の入力が不正である: {0}")]
    可視ID列不正(#[from] crate::visible_instance_selection::可視ID列エラー),
    #[error("カメラ相対フレームへの変換が失敗した: {0}")]
    カメラ相対変換失敗(blitz_math::座標変換エラー), // 非有限値・f32範囲外
    #[error("フレームの入力がレンダラーの構成・提示先・資源と噛み合わない: {0}")]
    フレーム入力不一致(#[from] frame_input_mismatch::フレーム入力不一致エラー),
    #[error("空の入力が不正である(層ごとの詳細は空エラー): {0}")]
    空不正(#[from] sky::空エラー),
    #[error("材質資源表の構築が失敗した: {0}")]
    材質資源表不正(#[from] material_table::材質資源表エラー), // 索引化した材質テクスチャ表の台帳と世代の失敗
    #[error("多段シャドウの構築が失敗した: {0}")]
    多段不正(#[from] cascade::多段エラー),
    #[error("照明問い合わせ資源の梱包が失敗した: {0}")]
    照明問い合わせ梱包不正(#[from] lighting_query::照明問い合わせ梱包エラー), // ヘッダ件数・実レコード数・容量の不整合
    #[error("パイプライン台帳とキーが噛み合わない: {0}")]
    パイプライン台帳不正(#[from] pipeline_ledger::パイプライン台帳エラー),
    #[error("間接照明の供給元の対応が破れた: {0}")]
    間接照明不正(#[from] indirect_lighting::間接照明エラー),
    #[error("生成に渡した素材とフレーム構成が噛み合わない: {0}")]
    生成要求不一致(#[from] generate_request::生成要求不一致エラー),
    #[error("局所可視性補正の入力が値域を外れた: {0}")]
    局所可視性不正(#[from] crate::local_visibility::局所可視性エラー),
}
