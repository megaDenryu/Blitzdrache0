//! レンダラーの生成・描画・破棄で起こりうる失敗を1つに畳んだ層のエラー型。担当するのは、層ごとのエラーと
//! Vulkanの失敗コードを呼び出し元へ`?`で伝播できる1つの型に束ねることである。
//!
//! 注意: `From<ash::LoadingError>` / `From<ash::vk::Result>` はash型を「受け取って自前表現へ変換する」だけであり、公開APIからash型を取り出せる経路にはならない。バリアント自体は自前表現(String・Vulkan失敗コード)のみを保持する。

use thiserror::Error;

use super::{cloth, device_requirement, frame_input_mismatch, lighting_query, material_table, pipeline_ledger, sky};
use crate::vulkan_failure::Vulkan失敗コード;

#[derive(Debug, Error)]
pub enum レンダラーエラー {
    /// Vulkanローダー(vulkan-1.dll)の動的読み込みに失敗した。
    #[error("Vulkanローダーの読み込みに失敗した: {0}")]
    ローダー読み込み失敗(String),
    /// Vulkan API呼び出しがエラーコードを返した。
    #[error("Vulkan呼び出しが失敗した: {0}")]
    Vulkan呼び出し失敗(Vulkan失敗コード),
    /// 物理デバイスがエンジンの最低要件を満たさない(適合デバイスなし・必要機能不足)。層ごとの詳細は`デバイス要件エラー`が持つ。
    #[error("物理デバイスがエンジンの最低要件を満たさない: {0}")]
    デバイス要件不足(#[from] device_requirement::デバイス要件エラー),

    /// サーフェスが提示可能な形式を1つも報告しなかった（Vulkan仕様上は到達しないはずの経路だが、外部デバイス由来のため型で防ぎきれない）。
    #[error("サーフェスが提示形式を1つも報告しなかった")]
    サーフェス形式なし,

    /// SPIR-Vバイト列の解釈（マジックナンバー確認・u32語への変換）に失敗した。`シェーダー一式` は4バイト整列を検証済みのため、ここに到達するのはslangcが不正なSPIR-Vを出力した場合のみ。
    #[error("SPIR-Vバイト列の読み込みに失敗した: {0}")]
    SPIRV読み込み失敗(String),

    /// ホスト可視かつコヒーレントなメモリ型が物理デバイスに1つも無かった（読み戻しバッファの確保に必要。Vulkan仕様上は到達しないはずの経路）。
    #[error("ホスト可視かつコヒーレントなメモリ型が見つからなかった")]
    ホスト可視メモリ型なし,

    /// サーフェスがTRANSFER_SRC用途をサポートせず、`一フレーム描画して読み戻す`が実行できない（判断9: ほぼ全環境で対応するが、非対応環境では通常描画のみ可能）。
    #[error("サーフェスがTRANSFER_SRC用途をサポートしないため読み戻せない")]
    読み戻し非対応,

    /// デバイスローカルなメモリ型が物理デバイスに1つも無かった（深度バッファの確保に必要。Vulkan仕様上は到達しないはずの経路）。
    #[error("デバイスローカルなメモリ型が見つからなかった")]
    デバイスローカルメモリ型なし,

    /// R8G8B8A8_SRGBのリニアフィルタblitに物理デバイスが対応していない（判断20: 縮小段マップ生成はvkCmdBlitImageの連鎖で行うため必須）。
    #[error("物理デバイスがR8G8B8A8_SRGBのリニアフィルタblitに対応していない")]
    テクスチャblit非対応,

    /// スキンメッシュ素材の属性数がレンダラー生成時の頂点数と一致しなかった(判断44)。
    #[error("スキン属性数{属性数}が頂点数{頂点数}と一致しない")]
    スキン属性数不一致 { 属性数: usize, 頂点数: usize },

    /// スキン付きシーンの有無とフレーム描画入力のスキン行列の有無が一致しなかった(判断44)。無言のデフォルト姿勢適用はしない(CLAUDE.md「不在・未設定・使用不可」)。
    #[error("スキン行列とスキンメッシュの有無が一致しない: {0}")]
    スキン行列不一致(String),

    /// M8最小実装の制約: スキン付きシーンを保持中のシーン差し替え(アセットホットリロード)は未対応。
    #[error("スキン付きシーンのシーン差し替えは未対応")]
    スキン付きシーン差し替え未対応,

    /// 布(判断52〜54)の失敗。布を持たない起動では起こらないため、層を分けて`布エラー`が持つ。
    #[error("布の入力が不正である: {0}")]
    布不正(#[from] cloth::布エラー),

    #[error("粒子シェーダーと粒子素材の有無が一致しない")]
    粒子入力不一致,

    #[error("描画対象のローカルからワールドへの変換が逆行列を持たない")]
    描画対象変換非可逆,

    /// 1つの描画対象が持つ個体の数がGPUの描画発行で表せる範囲を超えた。
    #[error("描画対象の個体数{0}がu32に収まらない")]
    個体数過大(usize),
    #[error("プリミティブのインデックス区間または頂点基準の値{0}が描画発行の幅に収まらない")]
    プリミティブ区間過大(u64),

    /// そのフレームの可視ID列の入力が満たすべき条件を破った。
    #[error("可視ID列の入力が不正である: {0}")]
    可視ID列不正(#[from] crate::visible_instance_selection::可視ID列エラー),

    /// 大域ワールド位置からカメラ相対位置へ狭める境界が失敗した(非有限値・f32範囲外)。
    #[error("カメラ相対フレームへの変換が失敗した: {0}")]
    カメラ相対変換失敗(blitz_math::座標変換エラー),

    #[error("フレームの入力がレンダラーの構成・提示先・資源と噛み合わない: {0}")]
    フレーム入力不一致(#[from] frame_input_mismatch::フレーム入力不一致エラー),

    #[error("空の入力が不正である(層ごとの詳細は空エラー): {0}")]
    空不正(#[from] sky::空エラー),

    /// 索引化した材質テクスチャ表の台帳と世代の失敗。旧スロット別セット経路では起こらないため、層を分けて`材質資源表エラー`が持つ。
    #[error("材質資源表の構築が失敗した: {0}")]
    材質資源表不正(#[from] material_table::材質資源表エラー),
    #[error("多段の組み立てが失敗した(カメラ視錐台の退化・正射影の値の不正): {0}")]
    多段構築失敗(#[from] crate::lighting_input::ライティング入力エラー),

    /// 照明問い合わせ資源の梱包で、ヘッダの件数と実レコード数と容量が整合しなかった。
    #[error("照明問い合わせ資源の梱包が失敗した: {0}")]
    照明問い合わせ梱包不正(#[from] lighting_query::照明問い合わせ梱包エラー),
    #[error("パイプライン台帳とキーが噛み合わない: {0}")]
    パイプライン台帳不正(#[from] pipeline_ledger::パイプライン台帳エラー),
}
