//! テクスチャの格納形式が機材の対応または用途と噛み合わないときの失敗。レンダラー層のエラーから分けて持つのは、
//! ここに挙げる失敗がテクスチャ1枚をGPUへ載せる局面でだけ起こり、どれも「この形式のテクスチャはこの経路では載せられない」
//! という同じ結論へ帰着するためである。`レンダラーエラー`へは`#[from]`で合流する。

use thiserror::Error;

use crate::texture_material::{テクスチャ格納形式, テクスチャ用途};

/// `リニアフィルタblit非対応`は、非圧縮のテクスチャの縮小段をvkCmdBlitImageの連鎖で作るため、
/// リニアフィルタのblitへの対応が必須になることに由来する(判断20)。
/// `ブロック圧縮の標本化非対応`は、ブロック圧縮の画像がblitを1度も通らずbufferからimageへのコピーで積んで
/// 標本化するだけであることに由来し、その2つの対応を機材へ問い合わせて確かめる
/// (参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`「判断e」)。
/// `格納形式と用途の組が未対応`は、初版のブロック圧縮がベースカラーのsRGBの色だけであり線形データを運ぶ組を
/// 持たないことに由来する。無言で非圧縮の画像形式へ落とすとGPUが別の並びとして復号するため、ここで明示的に失敗させる。
#[derive(Debug, Error)]
pub enum テクスチャ形式エラー {
    #[error("物理デバイスが非圧縮テクスチャのリニアフィルタblitに対応していない")]
    リニアフィルタblit非対応,
    #[error("物理デバイスがブロック圧縮テクスチャの標本化または転送先としての利用に対応していない")]
    ブロック圧縮の標本化非対応,
    #[error("テクスチャ格納形式{格納形式:?}と用途{用途:?}の組に対応する画像形式が無い")]
    格納形式と用途の組が未対応 {
        格納形式: テクスチャ格納形式, 用途: テクスチャ用途
    },
}
