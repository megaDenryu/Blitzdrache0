//! 描画定数16バイトのCPU側の並びと、シェーダー宣言との一致の検査。
//! 材質レコード添字が基準原点の余白と同じ位置にあることを数値で固定するのは、位置がずれると基準原点のwを添字として
//! 読むことになり、値化けとしてしか現れないためである。

use blitz_math::{大域メートル, 大域ワールド位置};

use super::{シーン描画定数, バイト長};
use crate::vulkan::relative_anchor::カメラ相対の基準原点;
use crate::vulkan::shader_struct::{シェーダー構造体の並び, 読み取る};

const 描画定数の原文: &str = include_str!("../../../../../shaders/scene_draw_constants.slang");

#[test]
fn 描画定数の各値が決めた開始位置へ並ぶ() {
    let バイト列 = 定数を作る().バイト列();
    assert_eq!(バイト列.len(), 16);
    assert_eq!(f32を読む(&バイト列, 0), 30.0);
    assert_eq!(f32を読む(&バイト列, 4), 31.0);
    assert_eq!(f32を読む(&バイト列, 8), 32.0);
    assert_eq!(u32を読む(&バイト列, 12), 7);
}

#[test]
fn 描画定数の宣言がcpu側と同じ並びである() {
    let 並び = match 読み取る(描画定数の原文, "SceneDrawConstants") {
        Ok(並び) => 並び,
        Err(誤り) => panic!("SceneDrawConstantsの宣言を読めない: {誤り}"),
    };
    assert_eq!(u32::try_from(並び.バイト長), Ok(バイト長));
    開始位置を確かめる(&並び, "position", 0);
    開始位置を確かめる(&並び, "materialRecordIndex", 12);
}

/// 基準原点は世界原点からカメラ大域原点を引いた値であるため、カメラを負の位置へ置くと基準原点が正の値になる。
fn 定数を作る() -> シーン描画定数 {
    let カメラ大域原点 = 大域ワールド位置::生成する(
        大域メートル::生成する(-30.0),
        大域メートル::生成する(-31.0),
        大域メートル::生成する(-32.0),
    );
    let 基準原点 = match カメラ相対の基準原点::世界原点から生成する(カメラ大域原点) {
        Ok(値) => 値,
        Err(誤り) => panic!("基準原点を作れない: {誤り}"),
    };
    シーン描画定数::生成する(基準原点, 7)
}

fn 開始位置を確かめる(並び: &シェーダー構造体の並び, 名前: &str, 期待する位置: usize) {
    match 並び.開始位置(名前) {
        Some(位置) => assert_eq!(位置, 期待する位置, "{名前}の開始位置がCPU側と食い違う"),
        None => panic!("{名前}がシェーダーの宣言に無い"),
    }
}

fn f32を読む(バイト列: &[u8], 位置: usize) -> f32 {
    f32::from_le_bytes(切り出す(バイト列, 位置))
}

fn u32を読む(バイト列: &[u8], 位置: usize) -> u32 {
    u32::from_le_bytes(切り出す(バイト列, 位置))
}

fn 切り出す(バイト列: &[u8], 位置: usize) -> [u8; 4] {
    match バイト列[位置..位置 + 4].try_into() {
        Ok(配列) => 配列,
        Err(_) => panic!("4バイトの切り出しに失敗した"),
    }
}
