//! 進行中フレームのスロットごとに1本ずつ持つホスト可視バッファの組と、その一括確保。
//!
//! 1本を全スロットで共有せずスロットごとに持つのは、あるスロットのフェンス待ちの後に書く規律だけで
//! 「別のスロットでまだ実行中のGPUが同じバッファを読んでいる」競合を消せるためである。
//! 組を1つの資源型にするのは、確保の途中で失敗したときの巻き戻しを1箇所へ閉じ、
//! スロットの添字とバッファの対応を取り違える余地を消すためである。
//!
//! 参照: _doc/計画/ユビキタス言語.md「資源型」

use ash::vk;

use super::{GPU資源の確保係, 専用メモリ付きバッファ};
use crate::error::レンダラーエラー;
use crate::vulkan::sync::{フレームスロット添字, 進行中フレーム数};
use crate::vulkan::tracked_device::GPUデバイス;

pub(crate) struct フレームスロットごとのバッファ {
    一覧: [専用メモリ付きバッファ; 進行中フレーム数],
}

impl フレームスロットごとのバッファ {
    pub(crate) fn スロットのバッファ(&self, スロット: フレームスロット添字) -> vk::Buffer {
        self.一覧[スロット.配列添字()].バッファ()
    }

    /// ディスクリプタが全スロットぶんの結び先を一度に要るときだけ使う。
    pub(crate) fn 全スロットのバッファ(&self) -> [vk::Buffer; 進行中フレーム数] {
        std::array::from_fn(|添字| self.一覧[添字].バッファ())
    }

    /// 前提: 呼び出し元はこのスロットのフェンス待機を済ませている。
    pub(crate) fn スロットの中身を書き換える(
        &self,
        device: &ash::Device,
        スロット: フレームスロット添字,
        データ: &[u8],
    ) -> Result<(), レンダラーエラー> {
        self.一覧[スロット.配列添字()].ホスト可視の中身を書き換える(device, データ)
    }

    /// 前提: 呼び出し元はこのスロットのフェンス待機を済ませている。
    pub(crate) fn スロットの一部を書き換える(
        &self,
        device: &ash::Device,
        スロット: フレームスロット添字,
        開始位置: usize,
        データ: &[u8],
    ) -> Result<(), レンダラーエラー> {
        self.一覧[スロット.配列添字()].ホスト可視の一部を書き換える(device, 開始位置, データ)
    }

    /// 前提: 呼び出し元はこのスロットのフェンス待機を済ませている。
    pub(crate) fn スロットのバッファへ32ビット整数列を書き込む(
        &self,
        device: &ash::Device,
        スロット: フレームスロット添字,
        値一覧: &[u32],
    ) -> Result<(), レンダラーエラー> {
        self.一覧[スロット.配列添字()].ホスト可視の先頭へ32ビット整数列を書き込む(device, 値一覧)
    }

    /// 巻き戻しの台帳が持つ控えを返す。控えと元は同じGPU資源を指すため、破棄するのはどちらか一方だけである。
    pub(super) fn 控え一覧を返す(&self) -> Vec<専用メモリ付きバッファ> {
        self.一覧.iter().map(専用メモリ付きバッファ::控えを返す).collect()
    }

    /// 前提: 呼び出し元はGPU側の使用完了を保証している。
    pub(crate) fn 破棄する(&self, device: &GPUデバイス) {
        for バッファ in &self.一覧 {
            バッファ.破棄する(device);
        }
    }
}

impl GPU資源の確保係<'_> {
    /// スロットの数だけ同じ内容のホスト可視バッファを確保する。途中で失敗したら、そこまでに確保したぶんをその場で破棄する。
    pub(crate) fn フレームスロットごとのホスト可視バッファを確保して書き込む(
        &self,
        データ: &[u8],
        用途: vk::BufferUsageFlags,
    ) -> Result<フレームスロットごとのバッファ, レンダラーエラー> {
        let mut 確保済み一覧 = Vec::with_capacity(進行中フレーム数);
        for _ in 0..進行中フレーム数 {
            match self.ホスト可視バッファを確保して書き込む(データ, 用途) {
                Ok(バッファ) => 確保済み一覧.push(バッファ),
                Err(誤り) => {
                    for バッファ in &確保済み一覧 {
                        バッファ.破棄する(self.論理デバイス());
                    }
                    return Err(誤り);
                }
            }
        }
        let Ok(一覧) = <[専用メモリ付きバッファ; 進行中フレーム数]>::try_from(確保済み一覧) else {
            panic!("進行中フレーム数ぶん確保したバッファが同じ数の配列にならなかった");
        };
        Ok(フレームスロットごとのバッファ { 一覧 })
    }
}
