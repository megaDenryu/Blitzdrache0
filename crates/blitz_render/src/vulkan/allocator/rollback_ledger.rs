//! 何本ものバッファを順に確保する組み立ての途中で失敗したとき、そこまでの確保を巻き戻す台帳。
//! 担当するのは確保の控えを積むことと、失敗した瞬間に控えを全部破棄することだけであり、
//! 何本をどの順で確保するかは呼び出し側が持つ。
//!
//! 台帳が持つのは控えであって所有権ではない。成功して組み上がった資源の破棄は、組み上がった型が引き受ける。

use super::{GPU資源の確保係, フレームスロットごとのバッファ, 専用メモリ付きバッファ};
use crate::error::レンダラーエラー;

pub(crate) struct 巻き戻せる確保の台帳<'確保係, 'デバイス> {
    確保係: &'確保係 GPU資源の確保係<'デバイス>,
    控え一覧: Vec<専用メモリ付きバッファ>,
}

impl<'確保係, 'デバイス> 巻き戻せる確保の台帳<'確保係, 'デバイス> {
    pub(crate) fn 始める(確保係: &'確保係 GPU資源の確保係<'デバイス>) -> Self {
        Self {
            確保係,
            控え一覧: Vec::new(),
        }
    }

    /// 確保の結果を受け取り、成功なら控えを残して確保したものをそのまま返し、
    /// 失敗ならそこまでに積んだ確保を全部破棄してから誤りを返す。
    pub(crate) fn 積む(
        &mut self,
        確保の結果: Result<専用メモリ付きバッファ, レンダラーエラー>,
    ) -> Result<専用メモリ付きバッファ, レンダラーエラー> {
        match 確保の結果 {
            Ok(確保済み) => {
                self.控え一覧.push(確保済み.控えを返す());
                Ok(確保済み)
            }
            Err(誤り) => Err(self.積んだ確保を全部破棄する(誤り)),
        }
    }

    /// フレームスロットの数だけまとめて確保したものを、同じ台帳へ1本ずつの控えとして積む。
    pub(crate) fn フレームスロットごとに積む(
        &mut self,
        確保の結果: Result<フレームスロットごとのバッファ, レンダラーエラー>,
    ) -> Result<フレームスロットごとのバッファ, レンダラーエラー> {
        match 確保の結果 {
            Ok(確保済み) => {
                self.控え一覧.extend(確保済み.控え一覧を返す());
                Ok(確保済み)
            }
            Err(誤り) => Err(self.積んだ確保を全部破棄する(誤り)),
        }
    }

    fn 積んだ確保を全部破棄する(&mut self, 誤り: レンダラーエラー) -> レンダラーエラー {
        for 控え in &self.控え一覧 {
            控え.破棄する(self.確保係.論理デバイス());
        }
        self.控え一覧.clear();
        誤り
    }
}
