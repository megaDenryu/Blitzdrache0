use super::実数列をリトルエンディアンで並べる;

#[test]
fn 実数の配列を配列と成分の順序どおりリトルエンディアンで書く() {
    let mut 書込先 = [0; 16];
    実数列をリトルエンディアンで並べる(&mut 書込先, &[[1.0, -2.0], [0.0, 0.5]]);
    assert_eq!(書込先, [0, 0, 128, 63, 0, 0, 0, 192, 0, 0, 0, 0, 0, 0, 0, 63]);
}

#[test]
fn 空の実数列は書込先を変えない() {
    let mut 書込先 = [];
    実数列をリトルエンディアンで並べる::<16>(&mut 書込先, &[]);
    assert_eq!(書込先, []);
}
