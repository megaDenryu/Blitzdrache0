//! ホストからこのバッファのメモリへ書き込む操作。担当するのは写像・書き込み・写像の解放という対の手順であり、
//! いつ呼んでよいかの同期は呼び出し元が持つ。
//!
//! 前提: このバッファはホスト可視かつコヒーレントなメモリで確保されている。
//! 注意: 呼び出し元は、そのフレームスロットのフェンス待ちを済ませてから呼ぶ。書き込み中のメモリをGPUが読んでいると内容が壊れる。

use ash::vk;

use super::専用メモリ付きバッファ;
use crate::error::レンダラーエラー;

/// 32ビット符号なし整数1つのバイト長。シェーダー側の`uint`1要素と一致する。
const 整数1つのバイト長: usize = 4;

impl 専用メモリ付きバッファ {
    /// 先頭からデータ長ぶんを置き換える。データ長が確保量を超えていればこの型が止める。
    pub(crate) fn ホスト可視の中身を書き換える(&self, device: &ash::Device, データ: &[u8]) -> Result<(), レンダラーエラー> {
        self.写像した先へ書き込む(device, データ.len(), |書込先| 書込先.copy_from_slice(データ))
    }

    /// 先頭から数えた位置へデータ長ぶんを置き換える。列の1要素だけを差し替えるときに使う。
    /// 開始位置とデータ長の和が確保量を超えていればこの型が止める。
    pub(crate) fn ホスト可視の一部を書き換える(
        &self,
        device: &ash::Device,
        開始位置: usize,
        データ: &[u8],
    ) -> Result<(), レンダラーエラー> {
        self.写像した先へ書き込む(device, 開始位置 + データ.len(), |書込先| {
            書込先[開始位置..].copy_from_slice(データ)
        })
    }

    /// 先頭から32ビット符号なし整数の列をリトルエンディアンで書き込む。
    /// 中間のバイト列を組まずに書くのは、これが毎フレームの経路であり、フレームごとの確保を持ち込まないためである。
    /// 値の数の4倍が確保量を超えていればこの型が止める。
    pub(crate) fn ホスト可視の先頭へ32ビット整数列を書き込む(
        &self,
        device: &ash::Device,
        値一覧: &[u32],
    ) -> Result<(), レンダラーエラー> {
        self.写像した先へ書き込む(device, 値一覧.len() * 整数1つのバイト長, |書込先| {
            整数列をリトルエンディアンで並べる(書込先, 値一覧);
        })
    }

    /// 写像している間だけ有効な書込先を作り、書き終えたら写像を解く。
    /// 写像の有効な区間を決めるのはこの手順であるため、何を書くかだけを呼び出し側から受け取る。
    ///
    /// 注意: `書く`の中でpanicするとこの手順の写像の解放へ到達せず、そのメモリは写像されたまま残る。
    /// ここで受け取るのは同じ長さのバイト列を埋めるだけの手であり、panicするのは長さの計算が壊れているとき、
    /// つまりプログラムのバグのときだけである。その場合は描画ループごと畳んで終えるため、写像の残りを解く経路は置かない。
    fn 写像した先へ書き込む(
        &self,
        device: &ash::Device,
        書き込む長さ: usize,
        書く: impl FnOnce(&mut [u8]),
    ) -> Result<(), レンダラーエラー> {
        self.写像で触る長さが確保量に収まることを確かめる(書き込む長さ);
        // 安全性: memoryはHOST_VISIBLE|HOST_COHERENTで確保済み。WHOLE_SIZEでの写像は確保量全体を対象にする。
        let ポインタ = unsafe { device.map_memory(self.memory, 0, vk::WHOLE_SIZE, vk::MemoryMapFlags::empty())? };
        // 安全性: ポインタは写像が返した確保量全体の先頭であり、書き込む長さが確保量以下であることを呼び出し元が保証する。
        let 書込先 = unsafe { std::slice::from_raw_parts_mut(ポインタ.cast::<u8>(), 書き込む長さ) };
        書く(書込先);
        // 安全性: memoryはこの直前に写像済みの同一ハンドルである。
        unsafe { device.unmap_memory(self.memory) };
        Ok(())
    }
}

fn 整数列をリトルエンディアンで並べる(書込先: &mut [u8], 値一覧: &[u32]) {
    for (区画, 値) in 書込先.chunks_exact_mut(整数1つのバイト長).zip(値一覧) {
        区画.copy_from_slice(&値.to_le_bytes());
    }
}
