//! 布ディスクリプタセットへの13バッファ書き込み。並びの順と番号と種別は`descriptor`が持つ束縛の宣言が決める。

use ash::vk;

use super::buffers::布バッファ;
use super::descriptor::束縛の本数;
use crate::vulkan::descriptor::{宣言から割り当てたセット, 結ぶ現物};
use crate::vulkan::sync::フレームスロット添字;

/// 前提: setは割り当て済みで、生成直後(GPU未使用)にのみ呼ばれる。
/// スキン済み頂点が無い(吊るし布=目標の更新対応0件、判断56)場合は9番目へ粒子バッファをダミー束縛する
/// (目標の確定のパスが積まれないため読まれない。レイアウト上の束縛だけが必要)。
pub(super) fn 布の束縛先をディスクリプタセットへ書き込む(
    device: &ash::Device,
    セット: &宣言から割り当てたセット<束縛の本数>,
    バッファ: &布バッファ,
    スキン済み頂点buffer: Option<vk::Buffer>,
    フレーム添字: フレームスロット添字,
) {
    セット.書き込み先(device).並びの位置ごとに結ぶ([
        結ぶ現物::バッファ全体(バッファ.定数一覧.スロットのバッファ(フレーム添字)),
        結ぶ現物::バッファ全体(バッファ.粒子.バッファのハンドル()),
        結ぶ現物::バッファ全体(バッファ.前位置.バッファのハンドル()),
        結ぶ現物::バッファ全体(バッファ.介入一覧.スロットのバッファ(フレーム添字)),
        結ぶ現物::バッファ全体(バッファ.拘束の引数.バッファのハンドル()),
        結ぶ現物::バッファ全体(バッファ.セルカウント.バッファのハンドル()),
        結ぶ現物::バッファ全体(バッファ.セル格納.バッファのハンドル()),
        結ぶ現物::バッファ全体(バッファ.布頂点.バッファのハンドル()),
        結ぶ現物::バッファ全体(スキン済み頂点buffer.unwrap_or(バッファ.粒子.バッファのハンドル())),
        結ぶ現物::バッファ全体(バッファ.目標の更新対応.バッファのハンドル()),
        結ぶ現物::バッファ全体(バッファ.ラグランジュ乗数.バッファのハンドル()),
        結ぶ現物::バッファ全体(バッファ.目標拘束の引数.バッファのハンドル()),
        結ぶ現物::バッファ全体(バッファ.目標位置.バッファのハンドル()),
    ]);
}
