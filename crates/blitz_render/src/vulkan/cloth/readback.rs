//! 布の粒子の位置とラグランジュ乗数の読み戻し。ホスト可視の受け皿(`readback_receptacle`)へ転送パスで粒子と乗数を写し、送信の完了後に読む。
//! 呼ばれるのは検収の突き合わせの終了時1回だけであり、毎フレームは呼ばない(Issue #36「描画経路」: XPBD化のために粒子状態を常時読み戻さない)。
//! コピーをグラフのパス宣言にするのは、直前の送信のコンピュート書きとコピーの間のバリアをグラフの導出に任せるためである。

use ash::vk;

use super::readback_receptacle::読み戻しの受け皿;
use super::布一式;
use crate::cloth_material::布の読み戻し;
use crate::error::レンダラーエラー;
use crate::vulkan::allocator::GPU資源の確保係;
use crate::vulkan::command_sink::積み込みを開始したコマンドバッファ;
use crate::vulkan::graph::{
    グラフ, グラフ実行器, バッファハンドル, バッファ用途, パス宣言, パス種別, 直前の送信でコンピュート書き直後状態
};
use crate::vulkan::tracked_device::GPUデバイス;
use crate::vulkan::transfer::転送実行環境;

impl 布一式 {
    /// 前提: 呼び出し元がGPUの全作業の完了を待っている(直前のフレームの布の工程が粒子と乗数を書き終えている)。
    pub(crate) fn 粒子と乗数を読み戻す(
        &self,
        確保係: &GPU資源の確保係<'_>,
        転送環境: &転送実行環境,
    ) -> Result<布の読み戻し, レンダラーエラー> {
        let 受け皿 = 読み戻しの受け皿::確保する(確保係, self.固定部.粒子数, self.固定部.拘束の数, self.固定部.目標拘束の数)?;
        let 結果 = self.受け皿へ写して読む(確保係.論理デバイス(), 転送環境, &受け皿);
        受け皿.破棄する(確保係.論理デバイス());
        結果
    }

    fn 受け皿へ写して読む(
        &self,
        device: &GPUデバイス,
        転送環境: &転送実行環境,
        受け皿: &読み戻しの受け皿,
    ) -> Result<布の読み戻し, レンダラーエラー> {
        let 一時 = 転送環境.転送コマンドを積み始める()?;
        let mut グラフ = グラフ::新規();
        let 粒子 = グラフ.バッファを登録する(self.バッファ.粒子.バッファのハンドル(), 直前の送信でコンピュート書き直後状態());
        let 乗数 = グラフ.バッファを登録する(
            self.バッファ.ラグランジュ乗数.バッファのハンドル(),
            直前の送信でコンピュート書き直後状態(),
        );
        コピーを積む(&mut グラフ, 受け皿, 粒子, 乗数);
        グラフ実行器::生成する(一時.積み先(), None).グラフを積む(グラフ);
        一時.送信して完了を待つ()?;
        受け皿.読む(device)
    }
}

/// 粒子と乗数を受け皿へ写す転送パスを積む。
fn コピーを積む<'a>(
    グラフ: &mut グラフ<'a>, 受け皿: &'a 読み戻しの受け皿, 粒子: バッファハンドル, 乗数: バッファハンドル
) {
    let 粒子のコピー = 受け皿.粒子のコピーの指定();
    let 乗数のコピー = 受け皿.乗数のコピーの指定();
    グラフ.パスを積む(パス宣言::生成する(
        "布読み戻し",
        Vec::new(),
        Vec::new(),
        vec![(粒子, バッファ用途::転送元), (乗数, バッファ用途::転送元)],
        Vec::new(),
        パス種別::転送,
        move |文脈| {
            let device = 文脈.積み先().論理デバイス();
            let command_buffer = 文脈.積み先().コマンドバッファ();
            // 安全性: command_bufferは記録中、転送元は用途の宣言からグラフがバリアを導き、受け皿は同じ長さで確保済みである。
            unsafe {
                device.cmd_copy_buffer(
                    command_buffer,
                    文脈.宣言済みのバッファを参照する(粒子),
                    粒子のコピー.受け,
                    &[vk::BufferCopy::default().size(粒子のコピー.バイト数)],
                );
                device.cmd_copy_buffer(
                    command_buffer,
                    文脈.宣言済みのバッファを参照する(乗数),
                    乗数のコピー.受け,
                    &[vk::BufferCopy::default().size(乗数のコピー.バイト数)],
                );
            }
        },
    ));
}
