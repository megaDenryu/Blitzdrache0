//! 布シミュ定数UBO(ClothParams、96バイト)のバイト列化。レイアウトは
//! shaders/cloth_step.slang冒頭の仕様と一致させる(std140。全メンバがvec4/uint4のため詰め物なし)。
//! 離す介入の復元値だった既定逆質量は持たない。固定と掴みは目標拘束であり、粒子の逆質量は物性のまま変わらない(判断6)。

use crate::cloth_material::{布の彩色の区間, 布定数};
use crate::frame_input::布フレーム入力;

pub(super) const バイト長: usize = 96;
pub(super) const 介入上限件数: u32 = 64;

pub(super) struct 固定部 {
    pub(super) 定数: 布定数,
    pub(super) 粒子数: u32,
    pub(super) 拘束の数: u32,
    pub(super) 目標拘束の数: u32,
    pub(super) 曲げ拘束の数: u32,
    pub(super) 色の区間一覧: Vec<布の彩色の区間>, // 彩色で並べ替えた拘束の並びの、色ごとの区間。生成後は変わらない
    pub(super) 曲げの色の区間一覧: Vec<布の彩色の区間>, // 曲げ拘束の彩色の色ごとの区間。距離拘束の色の後ろに積む
    pub(super) 一辺粒子数: u32,
    pub(super) 目標の更新対応の件数: u32,
}

pub(super) fn バイト列にする(固定: &固定部, 入力: &布フレーム入力) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(バイト長);
    // gravityDt
    f32列を積む(
        &mut バイト列,
        &[固定.定数.重力[0], 固定.定数.重力[1], 固定.定数.重力[2], 固定.定数.刻み幅.秒().値()],
    );
    // gridOrigin + セル寸法(=粒子間隔)
    f32列を積む(
        &mut バイト列,
        &[
            固定.定数.グリッド原点[0],
            固定.定数.グリッド原点[1],
            固定.定数.グリッド原点[2],
            固定.定数.粒子間隔,
        ],
    );
    // capsuleA + 半径
    f32列を積む(
        &mut バイト列,
        &[入力.カプセル端点a[0], 入力.カプセル端点a[1], 入力.カプセル端点a[2], 入力.カプセル半径],
    );
    // capsuleB + 予備
    f32列を積む(&mut バイト列, &[入力.カプセル端点b[0], 入力.カプセル端点b[1], 入力.カプセル端点b[2], 0.0]);
    // counts { 粒子数, 一辺, 介入件数, 目標拘束の数 }
    for 値 in [固定.粒子数, 固定.一辺粒子数, 入力.介入件数, 固定.目標拘束の数] {
        バイト列.extend_from_slice(&値.to_le_bytes());
    }
    // misc { 衝突半径(粒子間隔の0.4倍), 刻み幅の2乗の逆数, 速度減衰, 予備 }
    f32列を積む(
        &mut バイト列,
        &[固定.定数.粒子間隔 * 0.4, 固定.定数.刻み幅.刻み幅の2乗の逆数(), 固定.定数.速度減衰, 0.0],
    );
    バイト列
}

fn f32列を積む(バイト列: &mut Vec<u8>, 値一覧: &[f32]) {
    for 値 in 値一覧 {
        バイト列.extend_from_slice(&値.to_le_bytes());
    }
}
