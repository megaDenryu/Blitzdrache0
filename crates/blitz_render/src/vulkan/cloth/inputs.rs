//! 布一式が保持するハンドルと固定パラメータを、フレーム記録が読む`布描画入力`へ平坦化する。
//! 呼び出しタイミング: 毎フレームの描画入力組み立て時(生成完了後・破棄前であることは保持側の`レンダラー`が保証する)。

use super::布一式;
use crate::frame_input::布フレーム入力;
use crate::vulkan::frame::{布描画の外部資源, 布描画入力};
use crate::vulkan::relative_anchor::カメラ相対の基準原点;
use crate::vulkan::sync::フレームスロット添字;

impl 布一式 {
    pub(crate) fn 描画入力を作る(
        &self,
        フレーム添字: フレームスロット添字,
        フレーム入力: &布フレーム入力,
        相対の基準原点: カメラ相対の基準原点,
        外部資源: 布描画の外部資源,
    ) -> 布描画入力 {
        布描画入力 {
            layout: self.パイプライン群.layout,
            介入pipeline: self.パイプライン群.介入,
            積分pipeline: self.パイプライン群.積分,
            アタッチpipeline: self.パイプライン群.アタッチ,
            乗数零化pipeline: self.パイプライン群.乗数零化,
            拘束pipeline: self.パイプライン群.拘束,
            ハッシュ消去pipeline: self.パイプライン群.ハッシュ消去,
            ハッシュ格納pipeline: self.パイプライン群.ハッシュ格納,
            分離pipeline: self.パイプライン群.分離,
            仕上げpipeline: self.パイプライン群.仕上げ,
            頂点生成pipeline: self.パイプライン群.頂点生成,
            ディスクリプタセット: self.ディスクリプタ.セットのハンドル(フレーム添字),
            粒子数: self.固定部.粒子数,
            拘束の数: self.固定部.拘束の数,
            色の区間一覧: self.固定部.色の区間一覧.clone(),
            アタッチ件数: self.固定部.アタッチ件数,
            介入件数: フレーム入力.介入件数,
            進める刻み数: フレーム入力.進める刻み数,
            粒子バッファ: self.バッファ.粒子.バッファのハンドル(),
            前位置バッファ: self.バッファ.前位置.バッファのハンドル(),
            拘束の引数バッファ: self.バッファ.拘束の引数.バッファのハンドル(),
            ラグランジュ乗数バッファ: self.バッファ.ラグランジュ乗数.バッファのハンドル(),
            セルカウントバッファ: self.バッファ.セルカウント.バッファのハンドル(),
            セル格納バッファ: self.バッファ.セル格納.バッファのハンドル(),
            布頂点バッファ: self.バッファ.布頂点.バッファのハンドル(),
            インデックスバッファ: self.バッファ.インデックス.バッファのハンドル(),
            インデックス数: self.インデックス数,
            描画pipeline: self.描画パイプライン.handle,
            描画layout: self.描画パイプライン.パイプラインレイアウトのハンドル(),
            相対の基準原点,
            外部資源,
        }
    }
}
