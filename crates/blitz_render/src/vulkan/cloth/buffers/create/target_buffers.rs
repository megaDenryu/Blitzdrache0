//! 目標拘束の3本のバッファ(引数・目標位置・目標の更新対応)をGPUへ転送する。
//! 0件でも0バイトの確保はVulkanの契約違反のため、読まれない1件ぶんのダミーを置く(目標拘束0本なら目標拘束のパスは積まれず、
//! 更新対応0件なら目標の確定のパスは積まれない)。

use ash::vk;

use crate::cloth_material::布素材;
use crate::error::レンダラーエラー;
use crate::vulkan::allocator::{専用メモリ付きバッファ, 巻き戻せる確保の台帳};
use crate::vulkan::transfer::ステージング経由の転送係;

const 目標拘束1件のダミーのバイト数: usize = 8;
const 目標位置1件のダミーのバイト数: usize = 16;
const 更新対応1件のバイト数: usize = 8;

pub(super) struct 目標拘束のバッファ {
    pub(super) 引数: 専用メモリ付きバッファ,
    pub(super) 目標位置: 専用メモリ付きバッファ,
    pub(super) 更新対応: 専用メモリ付きバッファ,
}

pub(super) fn 目標拘束のバッファを生成する(
    台帳: &mut 巻き戻せる確保の台帳<'_, '_>,
    転送係: ステージング経由の転送係<'_>,
    素材: &布素材,
    ストレージ: vk::BufferUsageFlags,
) -> Result<目標拘束のバッファ, レンダラーエラー> {
    let 引数 = 台帳.積む(転送係.データからデバイスローカルバッファを確保する(
        &ダミーで埋める(&素材.目標拘束の引数バイト列, 目標拘束1件のダミーのバイト数),
        ストレージ,
    ))?;
    let 目標位置 = 台帳.積む(転送係.データからデバイスローカルバッファを確保する(
        &ダミーで埋める(&素材.目標位置の初期バイト列, 目標位置1件のダミーのバイト数),
        ストレージ,
    ))?;
    let mut 更新対応バイト列 = Vec::with_capacity(素材.目標の更新対応一覧.len() * 更新対応1件のバイト数);
    for 対応 in &素材.目標の更新対応一覧 {
        更新対応バイト列.extend_from_slice(&対応[0].to_le_bytes());
        更新対応バイト列.extend_from_slice(&対応[1].to_le_bytes());
    }
    let 更新対応 =
        台帳.積む(転送係.データからデバイスローカルバッファを確保する(
            &ダミーで埋める(&更新対応バイト列, 更新対応1件のバイト数),
            ストレージ,
        ))?;
    Ok(目標拘束のバッファ {
        引数, 目標位置, 更新対応
    })
}

/// 空のバイト列を、読まれない1件ぶんの零で置き換える。
fn ダミーで埋める(バイト列: &[u8], 一件のバイト数: usize) -> Vec<u8> {
    if バイト列.is_empty() {
        vec![0u8; 一件のバイト数]
    } else {
        バイト列.to_vec()
    }
}
