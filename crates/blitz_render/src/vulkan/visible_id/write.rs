//! 毎フレームの可視ID列の書き込み局面。フェンス待機の済んだフレームスロットのバッファへ、そのフレームの列を書く。
//! 触れるのはこのバッファが所有するホスト可視メモリだけであり、確保も解放も行わない。
//! 列の長さは個体がどのパスへ何回現れたかで変わるため、ここでは確保容量を超えないことだけを最後の砦として確かめる。
//! 区間の配置と値そのものの検査は呼び出し元の描画対象資源が済ませている。

use super::可視ID列バッファ;
use crate::error::レンダラーエラー;
use crate::visible_instance_selection::可視ID列エラー;
use crate::vulkan::sync::フレームスロット添字;

impl 可視ID列バッファ {
    pub(crate) fn 書き込む(
        &self,
        device: &ash::Device,
        フレーム添字: フレームスロット添字,
        可視id列: &[u32],
    ) -> Result<(), レンダラーエラー> {
        if 可視id列.len() > self.容量件数 {
            return Err(可視ID列エラー::容量超過 {
                列の長さ: 可視id列.len(),
                容量件数: self.容量件数,
            }
            .into());
        }
        if 可視id列.is_empty() {
            return Ok(());
        }
        self.スロットごとのバッファ
            .スロットのバッファへ32ビット整数列を書き込む(device, フレーム添字, 可視id列)
    }
}
