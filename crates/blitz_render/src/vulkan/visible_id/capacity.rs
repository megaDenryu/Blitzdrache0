//! 個体数から可視ID列の容量と確保時の中身を作る工程。受け取るのは描画対象の個体数、返すのは書き込める件数と
//! 確保時に書き込むバイト列である。バッファにもデバイスにも触れない。
//!
//! 容量が個体数のパス数倍なのは、1個体がシーンの区間と距離区分ごとの区間へ最大でパス数ぶん現れるためである。
//! 確保時の中身は0から個体数-1までの恒等の列をパス数ぶん繰り返したものであり、どのパスの区間の位置から読んでも
//! 恒等の列になる。可視個体選択を持たない描画対象は全パスの区間を先頭から読むため、この初期値のまま全個体を1つの段で描く。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」

use super::可視IDバイト長;
use crate::visible_instance_selection::可視ID列を読むパス数;

/// 個体数とパス数の積。どちらも実機の個体数から来る値であり、積がusizeを超えるのは呼び出し側が壊れた個体数を渡したときだけである。
pub(super) fn 容量件数を求める(個体数: u32) -> usize {
    let 件数 = usize::try_from(個体数).unwrap_or_else(|_| panic!("個体数がusizeに収まらない: {個体数}"));
    件数
        .checked_mul(可視ID列を読むパス数)
        .unwrap_or_else(|| panic!("可視ID列の容量件数がusizeに収まらない: 個体数{個体数}"))
}

pub(super) fn 初期バイト列を作る(個体数: u32) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(容量件数を求める(個体数) * 可視IDバイト長);
    for _ in 0..可視ID列を読むパス数 {
        for 添字 in 0..個体数 {
            バイト列.extend_from_slice(&添字.to_le_bytes());
        }
    }
    バイト列
}
