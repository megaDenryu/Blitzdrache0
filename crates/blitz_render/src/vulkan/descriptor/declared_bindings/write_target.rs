//! 宣言した束縛の並びに沿って、セット1枚へ現物を並び順で書き込む先。書ける番号と種別は宣言が決めるため、
//! 呼び出し側が渡すのは並びの位置ごとの現物だけである。
//!
//! 位置で受け取るのは、番号を呼び出し側に書かせないためである。番号を引数に取ると、宣言に無い番号や
//! 別のセットの番号を書く呼び出しが署名の上で成立する。件数が宣言と食い違う呼び出しは配列の長さで落ちる。

use ash::vk;

use super::bound_resource::結ぶ現物;
use super::宣言した束縛の並び;
use crate::vulkan::descriptor::ディスクリプタの書き込み先;

pub(crate) struct 宣言どおりに結ぶ書き込み先<'書き込み, const 本数: usize> {
    書き込み先: ディスクリプタの書き込み先<'書き込み>,
    宣言: 宣言した束縛の並び<本数>,
}

impl<'書き込み, const 本数: usize> 宣言どおりに結ぶ書き込み先<'書き込み, 本数> {
    pub(super) fn 生成する(
        device: &'書き込み ash::Device, セット: vk::DescriptorSet, 宣言: 宣言した束縛の並び<本数>
    ) -> Self {
        Self {
            書き込み先: ディスクリプタの書き込み先::生成する(device, セット),
            宣言,
        }
    }

    /// 宣言の並び順に現物を結ぶ。
    pub(crate) fn 並びの位置ごとに結ぶ(&self, 現物一覧: [結ぶ現物; 本数]) {
        for (位置, 現物) in 現物一覧.into_iter().enumerate() {
            self.並びの位置へ結ぶ(位置, 現物);
        }
    }

    /// 並びのうち1つの位置だけを結び直す。毎フレーム束縛先が変わる資源が1本だけあるセットが使う。
    /// 注意: バッファと画像の別が宣言の種別と食い違ったら、到達したらバグである状態としてpanicする。
    pub(crate) fn 並びの位置へ結ぶ(&self, 位置: usize, 現物: 結ぶ現物) {
        {
            let (番号, 種別, _) = self.宣言.位置の束縛(位置);
            match 現物 {
                結ぶ現物::バッファ全体(buffer) => {
                    バッファの種別であることを確かめる(位置, 種別);
                    self.書き込み先.バッファ全体を結ぶ(番号, 種別, buffer);
                }
                結ぶ現物::サンプラー付きの画像 {
                    ビュー,
                    サンプラー,
                    レイアウト,
                } => {
                    if 種別 != vk::DescriptorType::COMBINED_IMAGE_SAMPLER {
                        panic!("並びの{位置}番目はサンプラー付きの画像で結ばれたが、宣言の種別は{種別:?}である");
                    }
                    self.書き込み先.サンプラー付きの画像を結ぶ(番号, ビュー, サンプラー, レイアウト);
                }
                結ぶ現物::サンプラー無しの画像 { ビュー, レイアウト } => {
                    画像の種別であることを確かめる(位置, 種別);
                    self.書き込み先.画像1枚を結ぶ(番号, 種別, ビュー, レイアウト);
                }
            }
        }
    }
}

fn バッファの種別であることを確かめる(位置: usize, 種別: vk::DescriptorType) {
    if 種別 != vk::DescriptorType::UNIFORM_BUFFER && 種別 != vk::DescriptorType::STORAGE_BUFFER {
        panic!("並びの{位置}番目はバッファで結ばれたが、宣言の種別は{種別:?}である");
    }
}

fn 画像の種別であることを確かめる(位置: usize, 種別: vk::DescriptorType) {
    if 種別 != vk::DescriptorType::SAMPLED_IMAGE && 種別 != vk::DescriptorType::STORAGE_IMAGE {
        panic!("並びの{位置}番目はサンプラー無しの画像で結ばれたが、宣言の種別は{種別:?}である");
    }
}
