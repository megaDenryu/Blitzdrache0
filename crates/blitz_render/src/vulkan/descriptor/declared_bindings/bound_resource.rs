//! 宣言した並びの1つの位置へ結ぶ現物。バッファか画像かの別と、画像ならサンプラーを伴うかだけを数え上げる。
//!
//! どの種別として結ぶかを持たないのは、それを決めるのが宣言の側だからである。現物の側にも種別を持たせると、
//! 宣言と現物の2箇所に同じ事実が書かれ、食い違う組み合わせが作れてしまう。

use ash::vk;

#[derive(Clone, Copy)]
pub(crate) enum 結ぶ現物 {
    バッファ全体(vk::Buffer),
    サンプラー付きの画像 {
        ビュー: vk::ImageView,
        サンプラー: vk::Sampler,
        レイアウト: vk::ImageLayout,
    },
    サンプラー無しの画像 {
        ビュー: vk::ImageView,
        レイアウト: vk::ImageLayout,
    },
}
