//! 1つのフレームスロットが持つ照明問い合わせの5本のバッファを名前で束ねた値。
//! ディスクリプタの結び方だけを知る側へ、所有者が中身を渡すためにこの型がある。
//!
//! 5本を同じ型の位置引数で渡すと、順番を入れ替えても型が通ってしまい、
//! ヘッダの中身を方向光の列として読む描画が作れてしまう。名前で結ぶことでその間違いを閉じる。
//!
//! クラスタの2本も同じ組に入れるのは、選別のコンピュートが結ぶ生成側のセットが、この組の中の4本
//! (ヘッダ・局所光列・格子・光添字列)をそのまま読むためである。組を2つに分けると、同じスロットの資源が
//! 2つの経路で渡り、片方だけが別のスロットを指す取り違えが作れてしまう。

use ash::vk;

#[derive(Clone, Copy)]
pub(crate) struct 照明問い合わせのバッファ組 {
    pub(crate) ヘッダ: vk::Buffer,
    pub(crate) 方向光列: vk::Buffer,
    pub(crate) 局所光列: vk::Buffer,
    /// クラスタ格子のセルごとの区間表。選別のコンピュートが書き、画素段が読む。
    pub(crate) クラスタ格子: vk::Buffer,
    /// セルの区間が指す局所光レコードの添字の列。
    pub(crate) クラスタ光添字列: vk::Buffer,
}
