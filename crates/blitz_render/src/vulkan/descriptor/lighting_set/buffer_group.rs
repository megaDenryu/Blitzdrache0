//! 1つのフレームスロットが持つ照明問い合わせの3本のバッファを名前で束ねた値。
//! ディスクリプタの結び方だけを知る側へ、所有者が中身を渡すためにこの型がある。
//!
//! 3本を同じ型の位置引数で渡すと、順番を入れ替えても型が通ってしまい、
//! ヘッダの中身を方向光の列として読む描画が作れてしまう。名前で結ぶことでその間違いを閉じる。

use ash::vk;

#[derive(Clone, Copy)]
pub(crate) struct 照明問い合わせのバッファ組 {
    pub(crate) ヘッダ: vk::Buffer,
    pub(crate) 方向光列: vk::Buffer,
    pub(crate) 局所光列: vk::Buffer,
}
