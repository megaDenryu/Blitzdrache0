//! 照明問い合わせのセット(set3)へ現物を書き込む先。触れるのは1つのセットだけであり、直接光と影の4つの束縛番号を
//! このファイルが結ぶ。残りの番号は、その番号を持つモジュールが同じ型へ自分のメソッドを足して結ぶ。
//!
//! セットの役割ごとに型を分けるのは、材質のセットの束縛番号を照明問い合わせのセットへ書く呼び出しを、
//! 署名の上で成立させないためである。
//!
//! 呼び出しタイミング: 資源束の生成時にスロットごとに1回である(遠方環境の3つと局所可視度の画像は
//! 束縛先の画像が変わる局面があるため、それぞれの担当モジュールのメソッドが別に結び直す)。

use ash::vk;

use super::{
    cluster_grid, シャドウマップの束縛番号, ヘッダの束縛番号, 局所光列の束縛番号, 方向光列の束縛番号, 照明問い合わせのバッファ組
};
use crate::vulkan::descriptor::ディスクリプタの書き込み先;
use crate::vulkan::shadow_map::シャドウマップ;
use crate::vulkan::shadow_resources::影の資源の組;

#[derive(Clone, Copy)]
pub(crate) struct 照明問い合わせのセットの書き込み先<'書き込み>(ディスクリプタの書き込み先<'書き込み>);

impl<'書き込み> 照明問い合わせのセットの書き込み先<'書き込み> {
    pub(crate) fn 生成する(device: &'書き込み ash::Device, セット: vk::DescriptorSet) -> Self {
        Self(ディスクリプタの書き込み先::生成する(device, セット))
    }

    /// 自分の束縛番号を持つモジュールが、その番号だけを結ぶために借りる口。
    pub(super) fn ディスクリプタの書き込み先(&self) -> ディスクリプタの書き込み先<'書き込み> {
        self.0
    }

    /// そのスロットのバッファと、全スロットで共通の影の資源の組を結ぶ。
    /// クラスタ格子の2本も同じ手順で結ぶのは、どちらも同じスロットが所有するバッファであり、結び直しの局面を持たないためである。
    pub(crate) fn バッファ組と影の資源を結ぶ(
        &self, バッファ組: 照明問い合わせのバッファ組, 影の資源: &影の資源の組
    ) {
        self.多段影のシャドウマップを結ぶ(&影の資源.多段影);
        self.点光源の影の立方体配列を結ぶ(影の資源.点光源の影.立方体配列ビュー, 影の資源.点光源の影.sampler);
        self.0
            .バッファ全体を結ぶ(ヘッダの束縛番号, vk::DescriptorType::UNIFORM_BUFFER, バッファ組.ヘッダ);
        for (番号, buffer) in [(方向光列の束縛番号, バッファ組.方向光列), (局所光列の束縛番号, バッファ組.局所光列)]
        {
            self.0.バッファ全体を結ぶ(番号, vk::DescriptorType::STORAGE_BUFFER, buffer);
        }
        self.クラスタ格子の2本を結ぶ(バッファ組);
    }

    /// 束縛するのは距離区分ごとの層でなく配列全体のビューであり、距離区分の選択はシェーダーが層の添字で行う。
    /// シャドウマップはスワップチェーン再構築と独立の固定資源のため、生成時に一度だけ結べばよい。
    fn 多段影のシャドウマップを結ぶ(&self, シャドウマップ: &シャドウマップ) {
        self.0.サンプラー付きの画像を結ぶ(
            シャドウマップの束縛番号,
            シャドウマップ.配列ビュー,
            シャドウマップ.sampler,
            vk::ImageLayout::DEPTH_READ_ONLY_OPTIMAL,
        );
    }

    /// そのスロットのクラスタ格子の2本を結ぶ。番号と対応する値の並びは`cluster_grid`が持つ。
    fn クラスタ格子の2本を結ぶ(&self, バッファ組: 照明問い合わせのバッファ組) {
        for (番号, buffer) in cluster_grid::番号とバッファの対(バッファ組) {
            self.0.バッファ全体を結ぶ(番号, vk::DescriptorType::STORAGE_BUFFER, buffer);
        }
    }
}
