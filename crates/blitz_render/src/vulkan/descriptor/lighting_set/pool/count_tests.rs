//! プールの件数が進行中フレームスロットの数へ追従することの検査。
//! 実物のプールはGPUが要るため、件数の導き方だけをここで固定する。

use super::{スロット数をu32にする, セットあたりの件数};
use crate::vulkan::sync::進行中フレーム数;

#[test]
fn 件数はスロット数に比例する() {
    let スロット数 = スロット数をu32にする(進行中フレーム数);
    assert!(スロット数 >= 1);
    assert_eq!(セットあたりの件数.画像 * スロット数, スロット数);
    assert_eq!(セットあたりの件数.定数バッファ * スロット数, スロット数);
    assert_eq!(セットあたりの件数.ストレージバッファ * スロット数, 2 * スロット数);
}

#[test]
fn セット1つの件数はレイアウトの4つのバインディングと一致する() {
    let 合計 = セットあたりの件数.画像 + セットあたりの件数.定数バッファ + セットあたりの件数.ストレージバッファ;
    assert_eq!(合計, 4);
}
