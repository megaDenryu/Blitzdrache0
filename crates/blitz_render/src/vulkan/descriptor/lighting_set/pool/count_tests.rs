//! プールの件数が進行中フレームスロットの数と束縛レイアウトの枝へ追従することの検査。
//! 実物のプールはGPUが要るため、件数の導き方だけをここで固定する。

use super::{スロット数をu32にする, セット1つの件数, セットあたりの件数};
use crate::vulkan::pipeline_ledger::照明束縛レイアウト;
use crate::vulkan::sync::進行中フレーム数;

fn 束縛の総数(件数: &セット1つの件数) -> u32 {
    件数.サンプラー付き画像 + 件数.サンプラー無し画像 + 件数.定数バッファ + 件数.ストレージバッファ
}

#[test]
fn 件数はスロット数に比例する() {
    let スロット数 = スロット数をu32にする(進行中フレーム数);
    let 件数 = セットあたりの件数(照明束縛レイアウト::直接光と多段影);
    assert!(スロット数 >= 1);
    assert_eq!(件数.サンプラー付き画像 * スロット数, スロット数);
    assert_eq!(件数.サンプラー無し画像 * スロット数, スロット数);
    assert_eq!(件数.定数バッファ * スロット数, スロット数);
    assert_eq!(件数.ストレージバッファ * スロット数, 2 * スロット数);
}

#[test]
fn 定数近似の枝の件数はレイアウトの5つのバインディングと一致する() {
    let 件数 = セットあたりの件数(照明束縛レイアウト::直接光と多段影);
    assert_eq!(束縛の総数(&件数), 5);
}

#[test]
fn 遠方環境の枝の件数はレイアウトの8つのバインディングと一致する() {
    let 件数 = セットあたりの件数(照明束縛レイアウト::直接光と多段影と遠方環境);
    assert_eq!(束縛の総数(&件数), 8);
    assert_eq!(件数.サンプラー付き画像, 4);
}

/// 局所可視度の画像は拡散間接方式で枝を分けずに常に掛けるため、どちらの契約でも必ず1つ在る。
#[test]
fn 局所可視度の画像は両方の枝が1つずつ持つ() {
    for 束縛レイアウト in [照明束縛レイアウト::直接光と多段影, 照明束縛レイアウト::直接光と多段影と遠方環境]
    {
        assert_eq!(セットあたりの件数(束縛レイアウト).サンプラー無し画像, 1);
    }
}
