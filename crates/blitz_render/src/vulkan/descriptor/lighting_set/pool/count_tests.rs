//! プールの件数が進行中フレームスロットの数と束縛レイアウトの枝へ追従することの検査。
//! 実物のプールはGPUが要るため、件数の導き方だけをここで固定する。

use super::{スロット数をu32にする, セットあたりの件数};
use crate::vulkan::pipeline_ledger::照明束縛レイアウト;
use crate::vulkan::sync::進行中フレーム数;

#[test]
fn 件数はスロット数に比例する() {
    let スロット数 = スロット数をu32にする(進行中フレーム数);
    let 件数 = セットあたりの件数(照明束縛レイアウト::直接光と多段影);
    assert!(スロット数 >= 1);
    assert_eq!(件数.画像 * スロット数, スロット数);
    assert_eq!(件数.定数バッファ * スロット数, スロット数);
    assert_eq!(件数.ストレージバッファ * スロット数, 2 * スロット数);
}

#[test]
fn 定数近似の枝の件数はレイアウトの4つのバインディングと一致する() {
    let 件数 = セットあたりの件数(照明束縛レイアウト::直接光と多段影);
    assert_eq!(件数.画像 + 件数.定数バッファ + 件数.ストレージバッファ, 4);
}

#[test]
fn 遠方環境の枝の件数はレイアウトの7つのバインディングと一致する() {
    let 件数 = セットあたりの件数(照明束縛レイアウト::直接光と多段影と遠方環境);
    assert_eq!(件数.画像 + 件数.定数バッファ + 件数.ストレージバッファ, 7);
    assert_eq!(件数.画像, 4);
}
