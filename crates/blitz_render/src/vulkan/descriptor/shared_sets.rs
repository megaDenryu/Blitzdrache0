//! 描画対象の数に依らず1組だけ存在するディスクリプタセットの所有者。持つのはフレームスロットごとの
//! ビューとパスのセット(set0)だけである。材質のセット(set2)は資源表世代が、照明問い合わせのセット(set3)は
//! 照明問い合わせ資源束が持つため、束縛の組を作るときに外から受け取る。
//!
//! 束ごとに複製しないのは、内容が描画対象で変わらないためである。旧の巨大な共有セットは、
//! 描画対象数×材質スロット数×進行中フレーム数だけ同じ定数と同じシャドウマップを結び直していた
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「束縛頻度による4セット」)。
//! 生成の局面は`create`が持つ。

mod create;

use ash::vk;

use super::シーンセットレイアウト一式;
use crate::error::レンダラーエラー;
use crate::vulkan::frame::記録の計器;
use crate::vulkan::sync::{フレームスロット添字, 進行中フレーム数};
use crate::vulkan::uniform::フレームシェーダー定数一式;

/// 描画発行で変わらない3つのセットを1組にした束縛先。ビューとパスのセット(set0)と照明問い合わせのセット(set3)は
/// そのフレームスロットのもの、材質のセット(set2)はそのフレームが束縛する資源表世代のものである。
/// パイプラインレイアウトが違うと束縛が無効になるため、パイプラインを切り替えたパスの各局面がそれぞれ1回束縛する。
/// 計器を同じ組で運ぶのは、束縛を積む地点が必ずこの組を受け取るからである(数える場所と束縛する場所がずれない)。
#[derive(Clone, Copy)]
pub(crate) struct 共有セット束縛<'計器> {
    pub(crate) ビューとパス: vk::DescriptorSet,
    pub(crate) 材質: vk::DescriptorSet,
    pub(crate) 照明問い合わせ: vk::DescriptorSet,
    pub(crate) 計器: &'計器 記録の計器,
}

pub(crate) struct 共有ディスクリプタセット {
    pool: vk::DescriptorPool,
    ビューとパス一覧: [vk::DescriptorSet; 進行中フレーム数],
}

impl 共有ディスクリプタセット {
    pub(crate) fn 生成する(
        device: &ash::Device,
        レイアウト: &シーンセットレイアウト一式,
        シェーダー定数: &フレームシェーダー定数一式,
    ) -> Result<Self, レンダラーエラー> {
        create::生成する(device, レイアウト, シェーダー定数)
    }

    /// そのフレームスロットのビューとパスのセット。空パスと空中遠近合成パスがset0へ束縛する。
    pub(crate) fn ビューとパス(&self, フレーム添字: フレームスロット添字) -> vk::DescriptorSet {
        self.ビューとパス一覧[フレーム添字.配列添字()]
    }

    /// そのフレームのシーン描画・布描画・シャドウ記録が使う束縛先の組。材質のセットはそのフレームが束縛する世代のもの、
    /// 照明問い合わせのセットはそのフレームスロットのものを受け取る。
    pub(crate) fn 束縛を作る<'計器>(
        &self,
        フレーム添字: フレームスロット添字,
        材質: vk::DescriptorSet,
        照明問い合わせ: vk::DescriptorSet,
        計器: &'計器 記録の計器,
    ) -> 共有セット束縛<'計器> {
        共有セット束縛 {
            ビューとパス: self.ビューとパス(フレーム添字),
            材質,
            照明問い合わせ,
            計器,
        }
    }

    /// 注意: プールの破棄がセットの解放を暗黙に行う。
    /// 前提: レンダラー全体の破棄順は renderer/destroy.rs が持ち、この束はその1段として呼ばれる(GPU待機済み)。
    pub(crate) fn 破棄する(&self, device: &ash::Device) {
        // 安全性: poolはSelfが唯一の所有者であり、破棄時点でGPU側の使用完了を呼び出し元が保証する。
        unsafe { device.destroy_descriptor_pool(self.pool, None) };
    }
}
