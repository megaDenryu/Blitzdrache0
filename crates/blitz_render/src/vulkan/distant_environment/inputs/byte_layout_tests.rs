//! 遠方環境の即時定数のバイト並びを反証可能な形で固定する。担うのは、8つのスロットのどこに何が入るかと、
//! 全体が32バイトであることを値で確かめることだけである。
//!
//! 型検査ではこの並びを守れない。実数を8つ並べる関数はどの順に詰めても通り、順序を入れ替えても
//! シェーダー側が別の値を読むだけで、絵の明るさが変わるという形でしか誤りが現れない。

#![allow(clippy::unwrap_used)]

use super::{遠方環境の即時定数, 遠方環境の即時定数のバイト数};

/// スロットごとに違う値を入れる。並びを入れ替えた実装がこの値の並びを再現できないよう、
/// どの2つも等しくない値を選ぶ。
fn 検査する定数() -> 遠方環境の即時定数 {
    遠方環境の即時定数 {
        観測半径: 6_360_100.0,
        太陽天頂余弦: 0.5,
        太陽放射照度: 20.0,
        夜空放射輝度: [0.125, 0.25, 0.375],
    }
}

fn 実数の一覧(バイト列: &[u8]) -> Vec<f32> {
    バイト列
        .chunks_exact(4)
        .map(|語| f32::from_le_bytes([語[0], 語[1], 語[2], 語[3]]))
        .collect()
}

#[test]
fn バイト列の長さはレイアウトが宣言した枠と一致する() {
    let 長さ = 検査する定数().バイト列().len();
    assert_eq!(u32::try_from(長さ).unwrap(), 遠方環境の即時定数のバイト数);
}

#[test]
fn 全スロットの並びが固定されている() {
    let バイト列 = 検査する定数().バイト列();
    assert_eq!(実数の一覧(&バイト列), vec![6_360_100.0, 0.5, 20.0, 0.0, 0.125, 0.25, 0.375, 0.0]);
}

#[test]
fn 埋め草は4番目と8番目にある() {
    let 一覧 = 実数の一覧(&検査する定数().バイト列());
    assert_eq!(一覧[3], 0.0, "4番目の埋め草が0でない(夜空放射輝度の16バイト境界がずれる)");
    assert_eq!(一覧[7], 0.0, "8番目の埋め草が0でない");
}

#[test]
fn 値を1つ変えるとスロットが1つだけ変わる() {
    let 基準 = 実数の一覧(&検査する定数().バイト列());
    let mut 変えた定数 = 検査する定数();
    変えた定数.太陽放射照度 = 21.0;
    let 変えた = 実数の一覧(&変えた定数.バイト列());
    let 違う位置: Vec<usize> = (0..8).filter(|添字| 基準[*添字] != 変えた[*添字]).collect();
    assert_eq!(違う位置, vec![2], "太陽放射照度が3番目のスロット以外へ影響した");
}
