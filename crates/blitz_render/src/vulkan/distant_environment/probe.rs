//! ウィンドウを持たないGPUで大気のベイク済み画像と遠方環境を焼き、遠方環境の中身をホストへ読み戻す工程。
//! 受け取るのは媒体・解像度・観測条件・明るさの尺度・シェーダー、返すのは生の4成分と焼いた回数の観測である。
//!
//! 値オブジェクトでなく生の4成分で返すのは、検査が非有限値や負の値を観測できなければならないためである。
//! 検証済みの型で返すと、まさに検査したい壊れた値が構築の時点で弾かれてしまう。
//!
//! 大気のベイク済み画像を同じ実行で焼くのは、遠方環境がスカイビューのベイク済み画像を読むためである。
//! 本番と同じパス宣言を同じレンダーグラフへ積むため、バリアの導出も本番と同じ経路を通る。

mod copy_pass;
mod graph_build;
mod record;

use crate::atmosphere::{
    スカイビュー観測条件, 大気のベイク済み画像の解像度, 大気散乱媒体, 空中遠近観測条件, 遠方環境の解像度
};
use crate::compute_shader::コンピュートシェーダー;
use crate::error::レンダラーエラー;
use crate::shader_bundle::大気のベイク済み画像のシェーダー一式;
use crate::vulkan::atmosphere_lut::probe::検証観測;
use crate::vulkan::headless::ウィンドウなし実行GPU環境;

use super::遠方環境の即時定数;

/// 焼く条件一式。引数の列が伸び続けるのを避けて1つに束ねる。
pub(crate) struct 遠方環境を焼く条件<'a> {
    pub(crate) 媒体: &'a 大気散乱媒体,
    pub(crate) 大気の解像度: 大気のベイク済み画像の解像度,
    pub(crate) スカイビュー条件: スカイビュー観測条件,
    /// 空中遠近は焼かないが、大気の1フレーム入力が条件を要求するため受け取る(参照: `atmosphere_lut_input`)。
    pub(crate) 空中遠近条件: 空中遠近観測条件,
    pub(crate) 遠方環境の解像度: 遠方環境の解像度,
    pub(crate) 即時定数: 遠方環境の即時定数,
    pub(crate) 大気のシェーダー: &'a 大気のベイク済み画像のシェーダー一式,
    pub(crate) 遠方環境のシェーダー: &'a コンピュートシェーダー,
}

/// 読み戻した遠方環境の生の4成分。並びは面(層番号の順)が最も外、次に縦、横が最も速い。
/// CPU正本の`遠方環境を焼く`が返す並びと一致する。
pub(crate) struct 遠方環境の読み戻し {
    pub(crate) テクセル一覧: Vec<[f32; 4]>,
}

pub(crate) fn 遠方環境をgpuで焼いて読み戻す(
    条件: 遠方環境を焼く条件<'_>,
) -> Result<(遠方環境の読み戻し, 検証観測), レンダラーエラー> {
    let 環境 = ウィンドウなし実行GPU環境::生成する()?;
    let 結果 = record::環境で焼く(&環境, &条件);
    let 観測 = 検証観測::環境を破棄して観測する(&環境);
    Ok((結果?, 観測))
}
