//! 読み戻し検査が積むパスの並び。担当する工程は「透過率と多重散乱と遠方環境用スカイビューを本番と同じ宣言順で
//! 積み、その後ろへ本番と同じ遠方環境生成パスと立方体画像からバッファへのコピーを積む」ことである。
//!
//! 本番と同じパス宣言を使うのは、生成の完了とコピーの間のバリアを本番と同じ導出に任せるためである。
//! 手で書いたバリアで済ませると、検査だけが本番と違う同期の下で通ってしまう。
//!
//! 焼くスカイビューが空背景の読む連続な1枚でなく遠方環境用の1枚なのは、遠方環境の生成が束縛するのがそちらだからである。
//! 検査は正規化を通さない天頂余弦をそのまま与えるため、焼く内容は連続な1枚と同じである。

use ash::vk;

use super::copy_pass;
use crate::error::レンダラーエラー;
use crate::vulkan::atmosphere_lut::{
    pass as 大気パス, 大気のベイク済み画像の描画入力, 大気のベイク済み画像の生成入力, 大気のベイク済み画像の画像入力, 生成する組,
};
use crate::vulkan::distant_environment::{pass as 遠方環境パス, 遠方環境の生成入力, 遠方環境の画像入力};
use crate::vulkan::graph;
use crate::vulkan::headless::GPU命令を積む一時コマンドバッファ;

/// 1回の積み込みに要る材料。引数の列が伸び続けるのを避けて1つに束ねる。
pub(super) struct 積む材料<'a> {
    pub(super) 大気入力: &'a 大気のベイク済み画像の描画入力,
    /// 遠方環境用スカイビューを焼く1本ぶんの束縛と、その書き込み先の画像。
    pub(super) 遠方環境用スカイビュー入力: &'a 大気のベイク済み画像の生成入力,
    pub(super) 遠方環境用スカイビュー画像: &'a 大気のベイク済み画像の画像入力,
    pub(super) 遠方環境入力: &'a 遠方環境の生成入力,
    pub(super) 画像入力: &'a 遠方環境の画像入力,
    pub(super) 受け: vk::Buffer,
}

pub(super) fn パスを積んで送信し完了を待つ(
    一時: GPU命令を積む一時コマンドバッファ<'_>,
    材料: 積む材料<'_>,
) -> Result<(), レンダラーエラー> {
    let mut グラフ = graph::グラフ::新規();
    let スカイビュー = 大気の三枚を積む(&mut グラフ, &材料);
    let 遠方環境 = グラフ.画像を登録する(
        材料.画像入力.画像,
        材料.画像入力.ビュー,
        graph::画像アスペクト::カラー,
        graph::焼いた画像を焼き直すときの初期状態(),
        材料.画像入力.グラフへ渡す寸法,
    );
    グラフ.パスを積む(遠方環境パス::作る(
        遠方環境,
        vec![(スカイビュー, graph::画像用途::コンピュート読み)],
        材料.遠方環境入力,
    ));
    グラフ.パスを積む(copy_pass::作る(遠方環境, 材料.画像入力.範囲, 材料.画像入力.層数, 材料.受け));
    graph::グラフ実行器::生成する(一時.積み先(), None).グラフを積む(グラフ);
    一時.送信して完了を待つ()
}

/// 透過率・多重散乱・遠方環境用スカイビューを本番と同じ宣言順で積み、遠方環境が読むスカイビューのハンドルを返す。
/// 空中遠近を積まないのは、遠方環境がボリュームを1つも読まないためである。
/// 連続なスカイビューを積まないのは、この検査で誰も読まないためである。
fn 大気の三枚を積む<'a>(グラフ: &mut graph::グラフ<'a>, 材料: &積む材料<'a>) -> graph::画像ハンドル {
    let 入力 = 材料.大気入力;
    let 生成する組::全部 {
        透過率: 透過率入力,
        多重散乱: 多重散乱入力,
        ..
    } = &入力.焼く組
    else {
        panic!("遠方環境の読み戻し検査は大気の3枚すべてを焼く指示で呼ばれなければならない");
    };
    let 透過率 = 焼く画像を登録する(グラフ, &入力.透過率画像);
    let 多重散乱 = 焼く画像を登録する(グラフ, &入力.多重散乱画像);
    let スカイビュー = 焼く画像を登録する(グラフ, 材料.遠方環境用スカイビュー画像);
    グラフ.パスを積む(大気パス::作る("透過率生成", 透過率, Vec::new(), 透過率入力));
    let 透過率を読む = vec![(透過率, graph::画像用途::コンピュート読み)];
    グラフ.パスを積む(大気パス::作る("多重散乱生成", 多重散乱, 透過率を読む, 多重散乱入力));
    let 二枚を読む = vec![(透過率, graph::画像用途::コンピュート読み), (多重散乱, graph::画像用途::コンピュート読み)];
    グラフ.パスを積む(大気パス::作る(
        遠方環境パス::遠方環境用スカイビュー生成のパス名,
        スカイビュー,
        二枚を読む,
        材料.遠方環境用スカイビュー入力,
    ));
    スカイビュー
}

fn 焼く画像を登録する(
    グラフ: &mut graph::グラフ<'_>, 画像: &大気のベイク済み画像の画像入力
) -> graph::画像ハンドル {
    グラフ.画像を登録する(
        画像.画像,
        画像.ビュー,
        graph::画像アスペクト::カラー,
        graph::焼いた画像を焼き直すときの初期状態(),
        画像.形.グラフへ渡す寸法(),
    )
}
