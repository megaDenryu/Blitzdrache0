//! 読み戻し検査の資源のライフサイクル。担当する工程は「ウィンドウなし実行GPUの上に大気のベイク済み画像一式と
//! 遠方環境一式と受け皿を順に作り、記録を1回実行し、逆順に片付ける」ことである。
//! グラフへ何をどの順で積むかは`graph_build`が持つ。
//!
//! 大気のベイク済み画像を同じ実行で焼くのは、遠方環境がスカイビューのベイク済み画像を補間で読むためである。

use crate::atmosphere_lut_input::大気のベイク済み画像の生成指示;
use crate::error::レンダラーエラー;
use crate::vulkan::atmosphere_lut::readback_buffer::ベイク済み画像の読み戻しバッファ;
use crate::vulkan::atmosphere_lut::{大気のベイク済み画像一式, 描画入力の材料, 遠方環境用スカイビューの焼く条件};
use crate::vulkan::distant_environment::{遠方環境が借りる束縛先, 遠方環境一式};
use crate::vulkan::headless::ウィンドウなし実行GPU環境;
use crate::vulkan::sync::フレームスロット添字;

use super::graph_build;
use super::{遠方環境の読み戻し, 遠方環境を焼く条件};

pub(super) fn 環境で焼く(
    環境: &ウィンドウなし実行GPU環境,
    条件: &遠方環境を焼く条件<'_>,
) -> Result<遠方環境の読み戻し, レンダラーエラー> {
    let device = 環境.device();
    let 確保係 = 環境.資源の確保係を貸す();
    let 大気 = 大気のベイク済み画像一式::生成する(&確保係, 条件.大気の解像度, 条件.大気のシェーダー)?;
    let 結果 = 大気の上で焼く(環境, &大気, 条件, &確保係);
    大気.破棄する(device);
    結果
}

fn 大気の上で焼く(
    環境: &ウィンドウなし実行GPU環境,
    大気: &大気のベイク済み画像一式,
    条件: &遠方環境を焼く条件<'_>,
    確保係: &crate::vulkan::allocator::GPU資源の確保係<'_>,
) -> Result<遠方環境の読み戻し, レンダラーエラー> {
    let device = 環境.device();
    let 標本 = 大気.標本の束縛先();
    let シェーダー定数一覧 = 標本.シェーダー定数一覧;
    let 遠方環境 = 遠方環境一式::生成する(
        確保係,
        条件.遠方環境の解像度,
        遠方環境が借りる束縛先 {
            シェーダー定数一覧: &シェーダー定数一覧,
            遠方環境用スカイビュービュー: 大気.遠方環境用スカイビューのビュー(),
        },
        条件.遠方環境のシェーダー,
    )?;
    let 結果 = 受け皿を用意して焼く(環境, 大気, &遠方環境, 条件, 確保係);
    遠方環境.破棄する(device);
    結果
}

fn 受け皿を用意して焼く(
    環境: &ウィンドウなし実行GPU環境,
    大気: &大気のベイク済み画像一式,
    遠方環境: &遠方環境一式,
    条件: &遠方環境を焼く条件<'_>,
    確保係: &crate::vulkan::allocator::GPU資源の確保係<'_>,
) -> Result<遠方環境の読み戻し, レンダラーエラー> {
    let device = 環境.device();
    let スロット = フレームスロット添字::先頭();
    大気.媒体を書き込む(device, スロット, 条件.媒体)?;
    let 大気入力 = 大気.描画入力を作る(&描画入力の材料 {
        フレーム添字: スロット,
        媒体: 条件.媒体,
        スカイビュー条件: 条件.スカイビュー条件,
        空中遠近条件: 条件.空中遠近条件,
        指示: 大気のベイク済み画像の生成指示::全部焼き直す,
        空中遠近を参照するか: false,
    });
    let 遠方環境用スカイビュー入力 = 大気.遠方環境用スカイビューの生成入力(&遠方環境用スカイビューの焼く条件 {
        フレーム添字: スロット,
        媒体: 条件.媒体,
        スカイビュー条件: 条件.スカイビュー条件,
    });
    let 遠方環境用スカイビュー画像 = 大気.遠方環境用スカイビューの画像入力();
    let 遠方環境入力 = 遠方環境.生成入力を作る(スロット, 条件.即時定数);
    let 画像入力 = 遠方環境.画像入力を作る();
    let 受け皿 = ベイク済み画像の読み戻しバッファ::生成する(確保係, 条件.遠方環境の解像度.全テクセル数())?;
    let 材料 = graph_build::積む材料 {
        大気入力: &大気入力,
        遠方環境用スカイビュー入力: &遠方環境用スカイビュー入力,
        遠方環境用スカイビュー画像: &遠方環境用スカイビュー画像,
        遠方環境入力: &遠方環境入力,
        画像入力: &画像入力,
        受け: 受け皿.handle(),
    };
    let 積み込み結果 = 環境
        .gpu命令を積み始める()
        .and_then(|一時| graph_build::パスを積んで送信し完了を待つ(一時, 材料));
    let 結果 = 積み込み結果.and_then(|()| 受け皿.読み取る(device));
    受け皿.破棄する(device);
    Ok(遠方環境の読み戻し { テクセル一覧: 結果? })
}
