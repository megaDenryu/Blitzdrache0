//! 世代内材質レコードをシェーダーの`MaterialRecord`と一致する48バイトへ変換する。
//! 係数はどちらもvec4単位で置く。金属度と粗さは2成分しか使わないが、16バイト境界を跨がせないため4成分ぶんを占める。
//! 特徴ビットと役割ごとのテクスチャスロットは4バイトずつ続けて置く。並びは`材質テクスチャ役割::全役割`が正本である。

use crate::vulkan::material_table::{世代内材質レコード, 材質テクスチャ役割};

pub(crate) const バイト長: usize = 48;

pub(crate) fn バイト列にする(レコード: &世代内材質レコード) -> [u8; バイト長] {
    let mut バイト列 = [0u8; バイト長];
    let mut 位置 = 0usize;
    vec4を書き込む(&mut バイト列, &mut 位置, レコード.ベースカラー係数());
    vec4を書き込む(&mut バイト列, &mut 位置, [レコード.金属度係数(), レコード.粗さ係数(), 0.0, 0.0]);
    u32を書き込む(&mut バイト列, &mut 位置, レコード.特徴集合().生値());
    for 役割 in 材質テクスチャ役割::全役割 {
        u32を書き込む(&mut バイト列, &mut 位置, レコード.スロット(役割).添字());
    }
    バイト列
}

fn vec4を書き込む(バイト列: &mut [u8; バイト長], 位置: &mut usize, 値: [f32; 4]) {
    for 成分 in 値 {
        バイト列[*位置..*位置 + 4].copy_from_slice(&成分.to_le_bytes());
        *位置 += 4;
    }
}

fn u32を書き込む(バイト列: &mut [u8; バイト長], 位置: &mut usize, 値: u32) {
    バイト列[*位置..*位置 + 4].copy_from_slice(&値.to_le_bytes());
    *位置 += 4;
}
