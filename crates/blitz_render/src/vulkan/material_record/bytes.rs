//! 材質レコードをシェーダーの`MaterialRecord`と一致する32バイトへ変換する。
//! 係数はどちらもvec4単位で置く。金属度と粗さは2成分しか使わないが、16バイト境界を跨がせないため4成分ぶんを占める。

use super::content::材質レコード内容;

pub(crate) const バイト長: usize = 32;

pub(crate) fn バイト列にする(内容: &材質レコード内容) -> [u8; バイト長] {
    let mut バイト列 = [0u8; バイト長];
    let mut 位置 = 0usize;
    vec4を書き込む(&mut バイト列, &mut 位置, 内容.ベースカラー係数);
    vec4を書き込む(&mut バイト列, &mut 位置, [内容.金属粗さ係数[0], 内容.金属粗さ係数[1], 0.0, 0.0]);
    バイト列
}

fn vec4を書き込む(バイト列: &mut [u8; バイト長], 位置: &mut usize, 値: [f32; 4]) {
    for 成分 in 値 {
        バイト列[*位置..*位置 + 4].copy_from_slice(&成分.to_le_bytes());
        *位置 += 4;
    }
}
