//! 材質レコード1件ぶんの係数。画素段がテクスチャの標本へ掛ける値であり、テクスチャそのものは含まない。
//! 注意: この構造の並びはシェーダーの`MaterialRecord`と1対1で対応する。並びを変えると全材質の係数が入れ替わる。

use crate::material::マテリアル素材;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 材質レコード内容 {
    pub(crate) ベースカラー係数: [f32; 4],
    pub(crate) 金属粗さ係数: [f32; 2],
}

impl 材質レコード内容 {
    pub(crate) fn マテリアルから作る(マテリアル: &マテリアル素材) -> Self {
        Self {
            ベースカラー係数: マテリアル.ベースカラー係数(),
            金属粗さ係数: [マテリアル.金属度係数(), マテリアル.粗さ係数()],
        }
    }
}
