//! 粒子リソース一式が持つハンドルを、フレーム記録が読む1フレームぶんの描画入力へ平坦化する。
//! 呼び出しタイミング: 毎フレームの描画入力組み立て時(生成完了後・破棄前であることは保持側の`レンダラー`が保証する)。

use super::粒子リソース一式;
use crate::vulkan::frame::粒子描画入力;

impl 粒子リソース一式 {
    pub(crate) fn 描画入力を作る(&self, フレーム添字: usize) -> 粒子描画入力 {
        粒子描画入力 {
            コンピュートパイプライン: self.コンピュートパイプライン.handle,
            コンピュートlayout: self.コンピュートパイプライン.layout,
            描画パイプライン: self.描画パイプライン.handle,
            描画layout: self.描画パイプライン.layout,
            ディスクリプタセット: self.ディスクリプタ.set(フレーム添字),
            バッファ: self.バッファ.buffer,
            更新スレッド数: self.更新スレッド数,
            描画要素数: self.描画要素数,
        }
    }
}
