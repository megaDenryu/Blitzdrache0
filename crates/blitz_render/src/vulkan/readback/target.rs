//! 1フレームの読み戻しがどの画像をホストへ写すかの別。この判別が、確保するバッファの1画素あたりのバイト数と、グラフが転送元に選ぶ画像と、バッファの中身を開くときの成分の型の3つを同時に決める。
//!
//! 提示画像と圧縮前のHDRを型で分けるのは、明るさの圧縮とsRGB符号化を通った後の8ビット値から通す前の値を復元できないためである。
//! 絵の見え方でなく放射輝度そのものを測る検収は、圧縮前を読むほかに手立てが無い。
//! 最終深度が3つ目にあるのは、深度プリパスの三条件が同じ深度を作ったかどうかを、色と別に判定しなければならないためである。
//! 色が一致していても深度が違う状態は成立するため、1つの判定へまとめると条件の食い違いをどちらの側の破れとも決められない。
//! 局所可視度が4つ目にあるのは、局所可視性補正のslang写しをCPU正本と突き合わせる検収が、拡散間接照度へ掛かる前の係数そのものを読むためである。
//! 最終色から逆算すると材質の取り分と間接照明の値が混ざり、写しの誤りだけを取り出せない。
//! 動きベクトルが5つ目にあるのは、この画像がどの検収入口の絵にも現れないためである。色にも深度にも影響しない出力が意図どおり書かれていることは、その画像を直に読む以外に確かめる手立てが無い。
//! 今のフレームの色が6つ目にあるのは、時間再構成の検収が「履歴を無効にした直後の1フレーム目の結果が今のフレームの色と一致する」ことを画素で見るためである。圧縮前のHDRはその1フレームでは再構成の出力であり、突き合わせる相手を同じ画像から採れない。

use ash::vk;

/// 読み戻しの対象。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 読み戻し対象 {
    /// スワップチェーンへ提示した画像。明るさの圧縮とsRGB符号化を通った後の8ビット4成分である。
    提示画像,
    /// 明るさの圧縮パスが読む前のHDR中間画像。リニアの半精度4成分であり、露出倍率を掛ける前の値を持つ。
    圧縮前のHDR,
    /// そのフレームの全パスが書き終えた後の深度バッファ。単精度1成分である。
    最終深度,
    /// 両側ぼかしが書いた後の局所可視度画像。8ビット無符号正規化の4成分であり、意味を持つのは第1成分だけである。
    局所可視度,
    /// シーン描画と空のパスが書いた後の動きベクトル画像。半精度2成分であり、正規化装置座標の横と縦の差分を持つ。
    動きベクトル,
    /// 時間再構成のパスが読む前の、シーン・空・粒子が描いた色。リニアの半精度4成分であり、圧縮前のHDRと同じ並びを持つ。
    今のフレームの色,
}

impl 読み戻し対象 {
    /// 読み戻しバッファが1画素あたりに要するバイト数。提示画像と局所可視度はRGBA8の4バイト、動きベクトルは半精度2成分の4バイト、
    /// HDR中間画像は半精度4成分の8バイト、最終深度は単精度1成分の4バイトである。
    pub(crate) const fn 画素あたりバイト数(self) -> u64 {
        match self {
            Self::提示画像 | Self::最終深度 | Self::局所可視度 | Self::動きベクトル => 4,
            Self::圧縮前のHDR | Self::今のフレームの色 => 8,
        }
    }

    /// 転送元の画像から写す面。深度画像は色の面を持たない。
    pub(crate) const fn 画像の面(self) -> vk::ImageAspectFlags {
        match self {
            Self::提示画像 | Self::圧縮前のHDR | Self::局所可視度 | Self::動きベクトル | Self::今のフレームの色 => {
                vk::ImageAspectFlags::COLOR
            }
            Self::最終深度 => vk::ImageAspectFlags::DEPTH,
        }
    }
}
