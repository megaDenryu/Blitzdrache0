//! 1フレームの読み戻しがどの画像をホストへ写すかの別。この判別が、確保するバッファの1画素あたりのバイト数と、
//! グラフが転送元に選ぶ画像と、バッファの中身を開くときの成分の型の3つを同時に決める。
//!
//! 2つを型で分けるのは、明るさの圧縮とsRGB符号化を通った後の8ビット値から通す前の値を復元できないためである。
//! 絵の見え方でなく放射輝度そのものを測る検収は、圧縮前を読むほかに手立てが無い。

/// 読み戻しの対象。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 読み戻し対象 {
    /// スワップチェーンへ提示した画像。明るさの圧縮とsRGB符号化を通った後の8ビット4成分である。
    提示画像,
    /// 明るさの圧縮パスが読む前のHDR中間画像。リニアの半精度4成分であり、露出倍率を掛ける前の値を持つ。
    圧縮前のHDR,
}

impl 読み戻し対象 {
    /// 読み戻しバッファが1画素あたりに要するバイト数。提示画像はRGBA8の4バイト、HDR中間画像は半精度4成分の8バイトである。
    pub(crate) const fn 画素あたりバイト数(self) -> u64 {
        match self {
            Self::提示画像 => 4,
            Self::圧縮前のHDR => 8,
        }
    }
}
