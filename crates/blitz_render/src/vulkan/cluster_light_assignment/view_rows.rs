//! 選別のコンピュートが押し込む即時定数の組み立て。受け取るのはカメラ相対ワールドからビュー空間への変換、
//! 返すのは`shaders/cluster_light_assignment.slang`の`ClusterAssignmentViewRows`と同じ並びのバイト列である。
//!
//! 変換を即時定数で運ぶのは、この値を読むのが選別のコンピュートだけだからである。照明問い合わせヘッダは
//! 画素段と選別の両方が読む値だけを運ぶ約束であり、片方しか読まない値をそこへ足すとその約束が崩れる。
//!
//! 3行だけを運ぶのは、写す先が位置であり同次座標の4行目を要らないためである。カメラ相対フレームでは視点が
//! 原点にあるため各行の4つ目の成分は0になるが、行をそのまま写すことで取り違えを作らない。

use blitz_math::{ビュー, ワールド, 変換};

/// 即時定数として押し込むバイト数。単精度4つの行が3つである。
pub(crate) const 即時定数のバイト数: usize = 48;

/// GPU境界(生値境界): 変換を行優先の3行へ並べ直してバイト列にする。列優先の配列から行を取り出すため、
/// 行`i`の成分`j`は列`j`の成分`i`である。
pub(super) fn 即時定数にする(カメラ相対ビュー変換: 変換<ワールド, ビュー>) -> [u8; 即時定数のバイト数] {
    let 列優先 = カメラ相対ビュー変換.gpu境界用列優先配列();
    let mut バイト列 = [0u8; 即時定数のバイト数];
    for 行番号 in 0..3 {
        for (列番号, 列) in 列優先.iter().enumerate() {
            let 開始 = (行番号 * 4 + 列番号) * 4;
            バイト列[開始..開始 + 4].copy_from_slice(&列[行番号].to_le_bytes());
        }
    }
    バイト列
}

#[cfg(test)]
mod tests {
    use blitz_math::{ビュー, メートル, ワールド, 位置, 変換};

    use super::即時定数にする;

    /// 行の並びが、位置へ変換を適用した答えと一致することを見る。並びを取り違えると、光の位置がビュー空間の
    /// 別の場所へ写り、絵にしか出ない形でセルの割り当てが狂う。
    #[test]
    fn 三行の内積は変換を適用した位置と一致する() {
        let 注視点 = 位置::<ワールド>::生成する(メートル::生成する(1.0), メートル::生成する(-2.0), メートル::生成する(3.0));
        let 原点 = 位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0));
        let 変換: 変換<ワールド, ビュー> = 変換::注視(原点, 注視点);
        let 対象 = 位置::<ワールド>::生成する(メートル::生成する(4.0), メートル::生成する(5.0), メートル::生成する(-6.0));
        let 期待 = 変換.適用する(対象);
        let バイト列 = 即時定数にする(変換);
        let 同次 = [4.0f32, 5.0, -6.0, 1.0];
        let 実測: Vec<f32> = (0..3).map(|行| 行の内積(&バイト列, 行, 同次)).collect();
        for (成分, 値) in [期待.x().値(), 期待.y().値(), 期待.z().値()].into_iter().enumerate() {
            assert!((実測[成分] - 値).abs() < 1.0e-5, "成分{成分}が食い違う(期待{値}・実測{})", 実測[成分]);
        }
    }

    fn 行の内積(バイト列: &[u8], 行: usize, 同次: [f32; 4]) -> f32 {
        (0..4)
            .map(|列| {
                let 開始 = (行 * 4 + 列) * 4;
                let 四バイト: [u8; 4] = バイト列[開始..開始 + 4].try_into().unwrap_or([0; 4]);
                f32::from_le_bytes(四バイト) * 同次[列]
            })
            .sum()
    }
}
