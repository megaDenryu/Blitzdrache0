//! クラスタ格子のセルへ局所光を割り当てる選別の資源の所有者。持つのはコンピュートパイプラインと、
//! 生成側のセットと、そのセットが結んだバッファのハンドルの写しである。
//!
//! 格子と光添字列のバッファ自体は照明問い合わせ資源束が所有する。書く側でなく読む側(画素段のセット)が
//! 資源の寿命を持つのは、その2本がフレームスロットごとの照明問い合わせ資源であり、同じスロットの寿命と
//! 書き換えの規律をヘッダやレコード列と共有するためである。
//!
//! 全世界がこの選別を通る。局所光が0件の世界も件数0のセルだけを持つ格子を作り、照明束縛レイアウトの枝も
//! パイプラインキーの成分も増やさない
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断f」)。

