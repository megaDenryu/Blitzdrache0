use crate::vulkan::tracked_device::GPUデバイス;

/// 1つの班が受け持つセルの数。`shaders/cluster_light_assignment.slang`の`clusterAssignmentThreadsPerGroup`と一致させる。
const 班1つが受け持つセル数: u32 = 64;

/// 1つのフレームスロットが束縛するものと、そのスロットが書く2本のハンドル。
struct クラスタ選別のスロット束縛 {
    セット: vk::DescriptorSet,
    格子: vk::Buffer,
    光添字列: vk::Buffer,
}

pub(crate) struct クラスタ選別一式 {
    ディスクリプタ: descriptor::クラスタ選別のディスクリプタ,
    パイプライン: pipeline::クラスタ選別のパイプライン,
    スロットごとの束縛: Vec<クラスタ選別のスロット束縛>,
}

impl クラスタ選別一式 {
    /// 呼び出しタイミング: レンダラー生成時の1回だけ。照明問い合わせ資源束が組み上がった後に呼ぶ。
    pub(crate) fn 生成する(
        device: &GPUデバイス,
        シェーダー: &コンピュートシェーダー,
        バッファ組一覧: &[照明問い合わせのバッファ組],
    ) -> Result<Self, レンダラーエラー> {
        let ディスクリプタ = descriptor::クラスタ選別のディスクリプタ::生成する(device, バッファ組一覧)?;
        let パイプライン = match pipeline::クラスタ選別のパイプライン::生成する(device, ディスクリプタ.レイアウト, シェーダー)
        {
            Ok(値) => 値,
            Err(誤り) => {
                ディスクリプタ.破棄する(device);
                return Err(誤り);
            }
        };
        let スロットごとの束縛 = ディスクリプタ
            .スロットごとのセット
            .iter()
            .zip(バッファ組一覧)
            .map(|(セット, 組)| クラスタ選別のスロット束縛 {
                セット: *セット,
                格子: 組.クラスタ格子,
                光添字列: 組.クラスタ光添字列,
            })
            .collect();
        Ok(Self {
            ディスクリプタ,
            パイプライン,
            スロットごとの束縛,
        })
    }

    /// 前提: レンダラー全体の破棄順は renderer/destroy.rs が持ち、この一式はその1段として呼ばれる(GPU待機済み)。
    pub(crate) fn 破棄する(&self, device: &GPUデバイス) {
        self.パイプライン.破棄する(device);
        self.ディスクリプタ.破棄する(device);
    }
}

/// 積む班の数。セルの総数を1班のセル数で割った切り上げである。
fn 積む班の数を求める() -> u32 {
    クラスタ格子の分割数::仮置きの分割数を返す().セルの総数().div_ceil(班1つが受け持つセル数)
}
