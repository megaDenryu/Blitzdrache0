//! 選別の資源を、フレーム記録が読む1フレーム入力へ平坦化する。
//! 呼び出しタイミング: 毎フレームの描画入力組み立て時(生成完了後・破棄前であることは保持側が保証する)。
//!
//! 2本のバッファの持ち主は照明問い合わせ資源束であり、ここが持つのはその写しのハンドルである。写しで足りるのは、
//! この2本が生成時に1度だけ作られ、スワップチェーン再構築でも作り直されないためである。

use ash::vk;

use blitz_math::{ビュー, ワールド, 変換};

use super::view_rows::{即時定数にする, 即時定数のバイト数};
use super::クラスタ選別一式;
use crate::vulkan::sync::フレームスロット添字;

/// 選別のパスが要るハンドルと即時定数と班の数。値として持ち回れる大きさに収めてあるのは、この入力が
/// 「そのフレームだけ存在しうる入力」ではなく全フレームで必ず在る入力であり、借用の束へ混ぜないためである。
///
/// `格子`と`光添字列`はレンダーグラフへ登録して用途を宣言する2本であり、書き込みの宣言がこの2本に立つ
/// ことで画素段の読みとの間へバリアが立つ。`即時定数`はカメラ相対ワールドからビュー空間への変換の3行。
///
/// 参照: `即時定数`の並びは`shaders/cluster_light_assignment.slang`の宣言と一致させる。
#[derive(Clone, Copy)]
pub(crate) struct クラスタ選別の描画入力 {
    pub(crate) 格子: vk::Buffer,
    pub(crate) 光添字列: vk::Buffer,
    pub(crate) pipeline: vk::Pipeline,
    pub(crate) layout: vk::PipelineLayout,
    pub(crate) セット: vk::DescriptorSet,
    pub(crate) 即時定数: [u8; 即時定数のバイト数],
    pub(crate) 班数: u32, // 積む班の数。セルの総数を1班のスレッド数で割った切り上げ
}

impl クラスタ選別一式 {
    pub(crate) fn 描画入力を作る(
        &self,
        フレーム添字: フレームスロット添字,
        カメラ相対ビュー変換: 変換<ワールド, ビュー>,
    ) -> クラスタ選別の描画入力 {
        let スロット = &self.スロットごとの束縛[フレーム添字.配列添字()];
        クラスタ選別の描画入力 {
            格子: スロット.格子,
            光添字列: スロット.光添字列,
            pipeline: self.パイプライン.パイプライン,
            layout: self.パイプライン.レイアウト,
            セット: スロット.セット,
            即時定数: 即時定数にする(カメラ相対ビュー変換),
            班数: super::積む班の数を求める(),
        }
    }
}
