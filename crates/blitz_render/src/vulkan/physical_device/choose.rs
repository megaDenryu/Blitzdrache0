//! 基礎要件を満たした候補一覧から1台を選ぶ規則。受け取るのは候補一覧、返すのは選んだ候補の添字である。
//!
//! 規則は4つある。材質テクスチャ表の索引化に要る機能を満たすこと、テクスチャのブロック圧縮に対応すること、
//! 立方体の配列画像に対応することがいずれも必須であり、3つを満たす候補の中ではdiscrete GPUを優先する。
//! どの機能も選定の後で照合すると、対応する別のGPUを積んだ機材で動けるのに起動が失敗するため、候補を絞る段階でこの条件を掛ける。
//! 1台も残らなかったときは、どの条件で落ちたのかを区別したエラーを作り、どのGPUが何を欠いたのかを残す。
//! 条件を順に掛けるのは、報告の粒度をそろえるためである。先に落ちた条件だけを報告し、後ろの条件は判定しない。

use super::candidate::選定候補;
use crate::error::device_requirement::機材別のディスクリプタ索引機能不足;
use crate::error::デバイス要件エラー;

pub(crate) fn 選ぶ(候補一覧: &[選定候補]) -> Result<usize, デバイス要件エラー> {
    let 索引に対応する候補: Vec<&選定候補> = 候補一覧.iter().filter(|候補| 候補.索引の最低要件を満たすか()).collect();
    if 索引に対応する候補.is_empty() {
        return Err(索引の不足を報告する(候補一覧));
    }
    let 圧縮に対応する候補: Vec<&選定候補> = 索引に対応する候補
        .iter()
        .copied()
        .filter(|候補| 候補.テクスチャのブロック圧縮に対応するか())
        .collect();
    if 圧縮に対応する候補.is_empty() {
        return Err(デバイス要件エラー::テクスチャのブロック圧縮非対応(
            機材名を並べる(&索引に対応する候補),
        ));
    }
    let 対応候補: Vec<&選定候補> = 圧縮に対応する候補
        .iter()
        .copied()
        .filter(|候補| 候補.立方体の配列画像に対応するか())
        .collect();
    let 選んだ候補 = 対応候補.iter().find(|候補| 候補.discreteか()).or_else(|| 対応候補.first());
    match 選んだ候補 {
        Some(候補) => Ok(候補.添字()),
        None => Err(デバイス要件エラー::立方体の配列画像非対応(
            機材名を並べる(&圧縮に対応する候補),
        )),
    }
}

/// 基礎要件を満たす候補が1台も無いのか、あるが索引の機能を欠くのかを区別して伝える。
fn 索引の不足を報告する(候補一覧: &[選定候補]) -> デバイス要件エラー {
    if 候補一覧.is_empty() {
        return デバイス要件エラー::適合物理デバイスなし;
    }
    let 内訳一覧 = 候補一覧
        .iter()
        .map(|候補| 機材別のディスクリプタ索引機能不足::生成する(候補.機材名().to_string(), 候補.索引の不足一覧()))
        .collect();
    デバイス要件エラー::ディスクリプタ索引機能不足(内訳一覧)
}

/// 条件を欠いた機材を名前で並べる。どの条件も欠ける機能が1つしかないため、索引の不足のように項目別の内訳を持たない。
fn 機材名を並べる(候補一覧: &[&選定候補]) -> Vec<String> {
    候補一覧.iter().map(|候補| 候補.機材名().to_string()).collect()
}
