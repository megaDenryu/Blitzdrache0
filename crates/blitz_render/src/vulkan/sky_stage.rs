//! 空段階の資源: 空パイプラインと、ベイク済み画像を参照する標本ディスクリプタと空中遠近合成の一式。
//! フレーム構成に空段階があるときだけ`描画段階資源`が保持し、空パスと合成パスの記録だけがこの一式を束縛する。
//!
//! 標本ディスクリプタをこの型が必ず持つのは、「空を描くのにベイク済み画像を参照するディスクリプタが無い」という状態を
//! 型で作れなくするためである。放射輝度の評価はパイプライン1つで完結し、画素段の中に方式の分岐を持たない
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「空の方式」)。
//! 生成の手順は`create`、毎フレームの束縛先の組み立ては`draw_input`、合成の対は`aerial_composite`が担う。

mod aerial_composite;
mod create;
mod draw_input;

use ash::vk;

pub(crate) use aerial_composite::空中遠近合成資源;

use crate::error::レンダラーエラー;
use crate::shader_bundle::空シェーダー;
use crate::vulkan::atmosphere_lut::{大気のベイク済み画像一式, 大気のベイク済み画像標本ディスクリプタ};
use crate::vulkan::pipeline::空パイプライン;

pub(crate) struct 空段階資源 {
    パイプライン: 空パイプライン,
    /// set1でスカイビューのベイク済み画像と透過率のベイク済み画像と媒体のシェーダー定数を結ぶ。
    標本: 大気のベイク済み画像標本ディスクリプタ,
    /// 空中遠近の全画面合成。`None`は起動指定で合成を切った状態である。合成が無いフレームは
    /// ボリュームを1枚も焼かないため、この`Option`が「焼くかどうか」も決める。
    合成: Option<空中遠近合成資源>,
}

/// 空段階の資源を組み立てるのに要る材料。
pub(crate) struct 空段階の生成要求<'a> {
    pub(crate) カラー形式: vk::Format,
    pub(crate) 深度形式: vk::Format,
    /// set0に結ぶシーンのディスクリプタセットレイアウト。空パス定数のbinding9とビュー・シーンパス定数のbinding3をここから読む。
    pub(crate) シーンlayout: vk::DescriptorSetLayout,
    pub(crate) シェーダー: &'a 空シェーダー,
    /// set1から参照するベイク済み画像の持ち主。フレーム構成に空段階があるときは必ず作られている。
    pub(crate) 大気のベイク済み画像: &'a 大気のベイク済み画像一式,
}

impl 空段階資源 {
    pub(crate) fn 生成する(device: &ash::Device, 要求: 空段階の生成要求<'_>) -> Result<Self, レンダラーエラー> {
        create::生成する(device, 要求)
    }

    /// 空中遠近ボリュームを参照する合成パスを持つか。ボリュームを焼くかどうかがこの1つで決まる。
    /// 誰も参照しないボリュームを焼く時間はそのまま無駄になるため、合成が無い構成では1枚も焼かない。
    pub(crate) fn 空中遠近合成があるか(&self) -> bool {
        self.合成.is_some()
    }

    /// 合成の一式。合成を持たない構成では`None`を返す。
    pub(crate) fn 合成(&self) -> Option<&空中遠近合成資源> {
        self.合成.as_ref()
    }

    /// 注意: 合成を空パイプラインより先に破棄する(合成のディスクリプタが大気のベイク済み画像の画像ビューを結んでいるため、
    /// 大気のベイク済み画像の破棄より前に片付ける必要がある)。空パイプラインを標本ディスクリプタより先に破棄するのは、
    /// パイプラインレイアウトがディスクリプタセットレイアウトを参照するためである。
    /// 前提: レンダラー全体の破棄順は renderer/destroy.rs が持ち、この一式は`描画段階資源`の1段として呼ばれる(GPU待機済み)。
    pub(crate) fn 破棄する(&self, device: &ash::Device) {
        if let Some(合成) = &self.合成 {
            合成.破棄する(device);
        }
        self.パイプライン.破棄する(device);
        self.標本.破棄する(device);
    }
}
