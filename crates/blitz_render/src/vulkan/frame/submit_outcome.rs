//! キューへの送信が成った後の、そのフレームの結末を表す型。担当するのは、送信を境に失敗の意味が変わることを呼び出し元へ型で伝えることである。
//!
//! 注意: この値を受け取れたことは、GPUがこのフレームのコマンドを受け取ったことを意味する。GPUはそのフレームが束縛した資源表世代を読むため、
//! 結末が失敗であっても呼び出し元は保持を記録してから失敗を返す。記録を飛ばすと、誰も保持していないと台帳が誤判定し、GPUが読んでいる最中の画像を退役させる。

use crate::error::レンダラーエラー;

pub(crate) enum 送信後の結末 {
    /// 提示まで到達した。`提示劣化`が真ならスワップチェーンの再構築が望ましい。
    提示まで成功 { 提示劣化: bool },
    /// 送信は成ったが、読み戻しの待機か提示で失敗した。
    送信後に失敗(レンダラーエラー),
}

impl 送信後の結末 {
    /// 提示まで成功していれば提示劣化を、送信の後で失敗していればその失敗を返す。
    /// 保持の記録を済ませた呼び出し元が、フレームの結末をそのまま`Result`へ戻すために使う。
    pub(crate) fn 提示劣化として取り出す(self) -> Result<bool, レンダラーエラー> {
        match self {
            Self::提示まで成功 { 提示劣化 } => Ok(提示劣化),
            Self::送信後に失敗(誤り) => Err(誤り),
        }
    }
}
