//! 1つのパスの記録が実際にGPUへ積んだ回数。担当するのは、作業領域が数えた発行の件数とは別の観測地点の値であることを、
//! 別の型として示すことである。
//!
//! 発行の件数でGPUの描画回数を代用しない。前者は作業領域の充填が積んだ入力の数であり、後者は記録が
//! `vkCmdDrawIndexed`を呼んだ回数である。2つが食い違ったら、記録の経路が発行を落としているか二重に積んでいる。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段6

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 記録側の計数 {
    描画数: u32,
    パイプライン切替: u32,
    材質切替: u32,
}

impl 記録側の計数 {
    pub(crate) const fn 生成する(描画数: u32, パイプライン切替: u32, 材質切替: u32) -> Self {
        Self {
            描画数,
            パイプライン切替,
            材質切替,
        }
    }

    /// 記録が`vkCmdDrawIndexed`を呼んだ回数。
    pub const fn 描画数(self) -> u32 {
        self.描画数
    }

    /// 記録が`vkCmdBindPipeline`を呼んだ回数。同じパスの中で布のように別のパイプラインで描く局面があれば、その切替もここに入る。
    pub const fn パイプライン切替(self) -> u32 {
        self.パイプライン切替
    }

    /// 直前に描いた発行の大域材質IDから変わった回数。1件目は直前が無いため必ず1回と数える。
    /// 材質を読まない布の描画とシャドウの記録はこの数へ加えないため、シャドウのパスの値は常に0である。
    pub const fn 材質切替(self) -> u32 {
        self.材質切替
    }
}
