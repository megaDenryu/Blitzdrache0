//! 点光源の影の記録が1フレームに受け取る入力の型。1発行ぶんの入力と、それを1本の列として渡す器の2つを持つ。
//!
//! 距離区分別のシャドウ入力と違い、面ごとに別々の列を持たない。面ごとの絞りはコマンド記録の地点で球の判定として行い、
//! そのフレームの記録の中だけで使う(参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断n」)。
//! 面ごとに列を持つと、影を落とす灯の件数と面の数の積だけ作業領域が増え、絞りの結果を先に持つ意味も無い。

use ash::vk;
use blitz_math::{メートル, ワールド, 位置};

use crate::vulkan::point_light_shadow_cull::面ごとの絞り;
use crate::vulkan::relative_anchor::カメラ相対の基準原点;

/// 点光源の影の記録が束縛するパイプラインと、そのパイプラインレイアウト。発行ごとに変わらないため、
/// 発行1件の入力とは別の値にする。
#[derive(Clone, Copy)]
pub(crate) struct 点光源の影の束縛 {
    pub(crate) pipeline: vk::Pipeline,
    pub(crate) layout: vk::PipelineLayout,
}

/// 点光源の影の記録の1発行ぶんの入力。可視ID列を読まないため、描くのはこの描画対象の全個体である。
pub(crate) struct 点光源の影の描画発行 {
    pub(crate) 頂点バッファ: vk::Buffer,
    pub(crate) インデックスバッファ: vk::Buffer,
    pub(crate) 先頭インデックス: u32, // この発行が描き始めるインデックスの位置。プリミティブごとに発行を分けるため、メッシュ全体の先頭とは限らない
    pub(crate) インデックス数: u32,
    pub(crate) 頂点基準: i32, // インデックスの値へ足す頂点番号。プリミティブが自分の頂点範囲を持つ形式のために運ぶ
    pub(crate) 個体数: u32,   // この描画対象が持つ個体の数。可視ID列を通さず、頂点段が個体変換をこの範囲でそのまま参照する
    pub(crate) ジオメトリセット: vk::DescriptorSet,
    pub(crate) 相対の基準原点: カメラ相対の基準原点,
    pub(crate) 絞りの球: Option<(位置<ワールド>, メートル)>, // 面ごとの絞りが読む、この描画対象の全個体を覆う球(カメラ相対)。動く個体を宣言した対象は値を持たず、どの面でも候補として通す
}

impl 点光源の影の描画発行 {
    /// この発行がその灯とその面の候補か。灯の影響半径の球で絞ってから面の錐台で分ける順で判定する。
    /// 球を持たない対象は常に候補である。
    pub(crate) fn 候補か(&self, 絞り: 面ごとの絞り) -> bool {
        match self.絞りの球 {
            Some((中心, 半径)) => 絞り.球が候補か(中心, 半径),
            None => true,
        }
    }
}
