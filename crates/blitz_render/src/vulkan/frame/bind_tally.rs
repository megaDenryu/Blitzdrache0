//! そのフレームのコマンド記録が、scene系のどのセット番号へ何回ディスクリプタセットを束縛したかの計器。
//! 担当するのは、束縛を実際に積んだ地点で数えることである。
//!
//! 記録の側から数えるのは、「材質のセットはパスごとに1回だけ」という契約が守られているかを、コードの読みでなく
//! 実行の値で確かめるためである。発行の数や材質の数に比例して増えていないかは数でしか分からない
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段4bの検収ゲート(iii))。
//! 注意: 内側の可変性で数えるのは、コマンド記録の閉包が共有参照しか捕らえられないためである。
//! 1フレームの記録は1つのスレッドが順に行うため、`Cell`で足りる。

use std::cell::Cell;

/// scene系のセット番号の数。0がビューとパス、1がジオメトリ、2が材質、3が照明問い合わせである。
pub(crate) const セット番号の数: usize = 4;

#[derive(Default)]
pub(crate) struct セット別束縛計数 {
    番号別: [Cell<u32>; セット番号の数],
}

impl セット別束縛計数 {
    /// 前提: 1フレームにつき記録を始める前に1回だけ呼ぶ。呼ばないと前のフレームの回数へ積み上がる。
    pub(crate) fn 数え直す(&self) {
        for 欄 in &self.番号別 {
            欄.set(0);
        }
    }

    /// scene系の契約の外にある番号は数えない。粒子やポスト処理のような別のレイアウトの束縛が混ざらないようにするためである。
    pub(crate) fn 数える(&self, セット番号: u32) {
        let Ok(添字) = usize::try_from(セット番号) else {
            return;
        };
        if let Some(欄) = self.番号別.get(添字) {
            欄.set(欄.get().saturating_add(1));
        }
    }

    pub(crate) fn 番号ごとの回数(&self) -> [u32; セット番号の数] {
        std::array::from_fn(|添字| self.番号別[添字].get())
    }
}
