//! そのフレームのコマンド記録が、可視ID列を読むパスごとに何回描いたか・何回パイプラインを束縛したか・何回材質が変わったかの計器。
//! 担当するのは、コマンドを実際に積んだ地点で数えることと、材質切替の数え方を1箇所に閉じることである。
//!
//! 材質切替は「直前に描いた発行の大域材質IDから変わった回数」であり、直前の材質IDもこの計器が持つ。持たせないと
//! 数え方が記録側の各局面へ散り、初回の扱いが局面ごとにずれる。1件目は直前が無いため必ず1回と数える。
//! 注意: 内側の可変性で数えるのは、コマンド記録の閉包が共有参照しか捕らえられないためである。
//! 1フレームの記録は1つのスレッドが順に行うため、`Cell`で足りる。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段6

use std::cell::Cell;

use super::record_counts::記録側の計数;
use crate::visible_instance_selection::{可視ID列を読むパス数, 可視パス};
use crate::vulkan::material_table::大域材質ID;

/// 1つのパスぶんの記録。触れるのは自分のパスの3つの回数と直前の材質IDだけである。
#[derive(Default)]
struct パス別欄 {
    描画数: Cell<u32>,
    パイプライン切替: Cell<u32>,
    材質切替: Cell<u32>,
    直前の材質id: Cell<Option<大域材質ID>>,
}

#[derive(Default)]
pub(crate) struct 記録側切替計数 {
    パス別: [パス別欄; 可視ID列を読むパス数],
}

impl 記録側切替計数 {
    /// 前提: 1フレームにつき記録を始める前に1回だけ呼ぶ。呼ばないと前のフレームの回数へ積み上がり、
    /// 直前の材質IDが前のフレームの最後の材質のまま残って1件目の切替を数え落とす。
    pub(crate) fn 数え直す(&self) {
        for 欄 in &self.パス別 {
            欄.描画数.set(0);
            欄.パイプライン切替.set(0);
            欄.材質切替.set(0);
            欄.直前の材質id.set(None);
        }
    }

    pub(crate) fn 描画を数える(&self, パス: 可視パス) {
        let 欄 = &self.パス別[パス.添字()];
        欄.描画数.set(欄.描画数.get().saturating_add(1));
    }

    pub(crate) fn パイプライン束縛を数える(&self, パス: 可視パス) {
        let 欄 = &self.パス別[パス.添字()];
        欄.パイプライン切替.set(欄.パイプライン切替.get().saturating_add(1));
    }

    /// これから描く発行の材質を見せる。直前と違えば材質切替を1つ数える。材質を読まない描画はこれを呼ばない。
    pub(crate) fn 材質を見る(&self, パス: 可視パス, 材質id: 大域材質ID) {
        let 欄 = &self.パス別[パス.添字()];
        if 欄.直前の材質id.get() != Some(材質id) {
            欄.材質切替.set(欄.材質切替.get().saturating_add(1));
            欄.直前の材質id.set(Some(材質id));
        }
    }

    pub(crate) fn パスの計数(&self, パス: 可視パス) -> 記録側の計数 {
        let 欄 = &self.パス別[パス.添字()];
        記録側の計数::生成する(欄.描画数.get(), 欄.パイプライン切替.get(), 欄.材質切替.get())
    }
}
