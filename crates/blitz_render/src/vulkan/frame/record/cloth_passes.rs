//! 布シミュレーションのコンピュートパス列(判断54): 介入→積分→アタッチ→拘束x4→
//! ハッシュ消去→格納→分離→仕上げ→頂点生成。各パスはバインド+ディスパッチのみで、
//! バリアはグラフのバッファ読み書き宣言から導出される。

use ash::vk;

use crate::vulkan::frame::布描画入力;
use crate::vulkan::graph::{グラフ, バッファ用途, バッファハンドル, パス宣言, パス種別, 前フレームコンピュート読み直後状態, 前フレーム頂点入力読み直後状態};

pub(super) struct 布ハンドル {
    pub(super) 布頂点: バッファハンドル,
    粒子: バッファハンドル,
    前位置: バッファハンドル,
    セルカウント: バッファハンドル,
    セル格納: バッファハンドル,
}

pub(super) fn 登録する<'a>(グラフ: &mut グラフ<'a>, 入力: &'a 布描画入力) -> 布ハンドル {
    布ハンドル {
        布頂点: グラフ.バッファを登録する(入力.布頂点バッファ, 前フレーム頂点入力読み直後状態()),
        粒子: グラフ.バッファを登録する(入力.粒子バッファ, 前フレームコンピュート読み直後状態()),
        前位置: グラフ.バッファを登録する(入力.前位置バッファ, 前フレームコンピュート読み直後状態()),
        セルカウント: グラフ.バッファを登録する(入力.セルカウントバッファ, 前フレームコンピュート読み直後状態()),
        セル格納: グラフ.バッファを登録する(入力.セル格納バッファ, 前フレームコンピュート読み直後状態()),
    }
}

const セル総数: u32 = 32 * 32 * 32;

/// スキン済みハンドルはアタッチパスの読み宣言に使う(判断52の合流点)。
pub(super) fn 積む<'a>(グラフ: &mut グラフ<'a>, 入力: &'a 布描画入力, ハンドル: &布ハンドル, スキン済み: バッファハンドル) {
    let 粒 = (ハンドル.粒子, バッファ用途::コンピュート読み書き);
    let 前 = (ハンドル.前位置, バッファ用途::コンピュート読み書き);
    積む1(グラフ, "布介入", vec![], vec![粒, 前], 入力, 入力.介入pipeline, 入力.介入件数.max(1));
    積む1(グラフ, "布積分", vec![], vec![粒, 前], 入力, 入力.積分pipeline, 入力.粒子数);
    積む1(グラフ, "布アタッチ", vec![(スキン済み, バッファ用途::コンピュート読み)], vec![粒, 前], 入力, 入力.アタッチpipeline, 入力.アタッチ件数.max(1));
    for 名前 in ["布拘束1", "布拘束2", "布拘束3", "布拘束4"] {
        積む1(グラフ, 名前, vec![], vec![粒], 入力, 入力.拘束pipeline, 入力.粒子数);
    }
    積む1(グラフ, "布ハッシュ消去", vec![], vec![(ハンドル.セルカウント, バッファ用途::コンピュート書き)], 入力, 入力.ハッシュ消去pipeline, セル総数);
    積む1(
        グラフ,
        "布ハッシュ格納",
        vec![(ハンドル.粒子, バッファ用途::コンピュート読み)],
        vec![(ハンドル.セルカウント, バッファ用途::コンピュート読み書き), (ハンドル.セル格納, バッファ用途::コンピュート書き)],
        入力,
        入力.ハッシュ格納pipeline,
        入力.粒子数,
    );
    積む1(
        グラフ,
        "布分離",
        vec![(ハンドル.セルカウント, バッファ用途::コンピュート読み), (ハンドル.セル格納, バッファ用途::コンピュート読み)],
        vec![粒],
        入力,
        入力.分離pipeline,
        入力.粒子数,
    );
    積む1(グラフ, "布仕上げ", vec![(ハンドル.前位置, バッファ用途::コンピュート読み)], vec![粒], 入力, 入力.仕上げpipeline, 入力.粒子数);
    積む1(
        グラフ,
        "布頂点生成",
        vec![(ハンドル.粒子, バッファ用途::コンピュート読み)],
        vec![(ハンドル.布頂点, バッファ用途::コンピュート書き)],
        入力,
        入力.頂点生成pipeline,
        入力.粒子数,
    );
}

#[allow(clippy::too_many_arguments)]
fn 積む1<'a>(
    グラフ: &mut グラフ<'a>,
    名前: &'static str,
    読み: Vec<(バッファハンドル, バッファ用途)>,
    書き: Vec<(バッファハンドル, バッファ用途)>,
    入力: &'a 布描画入力,
    pipeline: vk::Pipeline,
    スレッド数: u32,
) {
    let セット一覧 = [入力.ディスクリプタセット];
    let layout = 入力.layout;
    グラフ.パスを積む(パス宣言::生成する(名前, Vec::new(), Vec::new(), 読み, 書き, パス種別::コンピュート, move |文脈| {
        let device = 文脈.device();
        let command_buffer = 文脈.コマンドバッファ();
        // 安全性: command_bufferは記録中で、pipeline・ディスクリプタセットは生成済み。
        unsafe {
            device.cmd_bind_pipeline(command_buffer, vk::PipelineBindPoint::COMPUTE, pipeline);
            device.cmd_bind_descriptor_sets(command_buffer, vk::PipelineBindPoint::COMPUTE, layout, 0, &セット一覧, &[]);
            device.cmd_dispatch(command_buffer, スレッド数.div_ceil(64), 1, 1);
        }
    }));
}
