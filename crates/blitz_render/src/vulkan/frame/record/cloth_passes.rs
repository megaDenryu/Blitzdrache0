//! 布シミュレーションのコンピュートパス列(判断54): 介入→積分→アタッチ→拘束x4→
//! ハッシュ消去→格納→分離→仕上げを刻み数ぶん繰り返し、最後に頂点生成を1本積む。各パスはバインド+計算の発行のみで、
//! バリアはグラフのバッファ読み書き宣言から導出される。

mod dispatch;
mod sequence;
#[cfg(test)]
mod sequence_tests;

pub(crate) use sequence::一刻みのパス数;

use crate::vulkan::frame::布描画入力;
use crate::vulkan::graph::{
    グラフ, バッファハンドル, 前フレームコンピュート読み直後状態, 前フレーム頂点入力読み直後状態
};

pub(super) use sequence::積む;

pub(super) struct 布ハンドル {
    pub(super) 布頂点: バッファハンドル,
    粒子: バッファハンドル,
    前位置: バッファハンドル,
    セルカウント: バッファハンドル,
    セル格納: バッファハンドル,
}

pub(super) fn 登録する<'a>(グラフ: &mut グラフ<'a>, 入力: &'a 布描画入力) -> 布ハンドル {
    布ハンドル {
        布頂点: グラフ.バッファを登録する(入力.布頂点バッファ, 前フレーム頂点入力読み直後状態()),
        粒子: グラフ.バッファを登録する(入力.粒子バッファ, 前フレームコンピュート読み直後状態()),
        前位置: グラフ.バッファを登録する(入力.前位置バッファ, 前フレームコンピュート読み直後状態()),
        セルカウント: グラフ.バッファを登録する(入力.セルカウントバッファ, 前フレームコンピュート読み直後状態()),
        セル格納: グラフ.バッファを登録する(入力.セル格納バッファ, 前フレームコンピュート読み直後状態()),
    }
}
