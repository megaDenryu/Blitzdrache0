//! 深度プリパスと色パスのパス名の正本と、両者の1フレームぶんの合計を1つの区間として出す合成の宣言。
//!
//! 名前を1箇所へ置くのは、パス宣言と合成区間の宣言が同じ語を読まなければならないためである。別々に文字列を書くと、
//! 片方の綴りを変えたときに合成が黙って標本を作らなくなる(構成が1つでも欠けた合成は標本を作らない)。
//!
//! 合成が要るのは、分位の加法性が一般に成立しないためである。区間ごとの窓からp50を採って足した値は、
//! 1フレームの合計の分布から採ったp50ではない。深度プリパスを積む条件の費用は、この合成の分位で語る
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「IIaの実装設計」)。
//!
//! 深度プリパスを積まない条件ではこの合成の標本が1つも立たない。そのフレームの合計は色パスの区間そのものであり、
//! 足す相手が無いためである。

use crate::vulkan::gpu_timing::合成区間の宣言;

pub(crate) const 深度プリパス: &str = "深度プリパス";
pub(crate) const シーン描画: &str = "シーン描画";
pub(crate) const 深度プリパスとシーン描画の合計: &str = "深度プリパスとシーン描画の合計";

pub(crate) fn 合成区間を宣言する() -> 合成区間の宣言 {
    合成区間の宣言::生成する(深度プリパスとシーン描画の合計, vec![深度プリパス, シーン描画])
}
