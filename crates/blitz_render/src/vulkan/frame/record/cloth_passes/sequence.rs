//! 布シミュレーションの依存順にコンピュートパスを積む。
//!
//! シミュレーションの工程はその描画で進める刻み数ぶん繰り返す。1描画に1回だけ積む形は、布の進む速さが画面の
//! 書き換え頻度に比例する欠陥(毎秒120回書き換えるモニターで2倍速、毎秒30回で半速)をそのまま残すためである。
//! 可変の巨大な刻み幅を1回で進める形は採らない(判断4と同じ理由に加え、位置ベースの拘束解決が大きな刻みで暴れる)。
//! 頂点生成だけは刻み数と無関係に描画機会ごとに1回積む。粒子から描画用の頂点を作り直す工程であって時間を1つも
//! 進めないため、時間意味の区分では「描画機会ごと」に属する。刻み0本の描画でもこれを積むのは、確保直後の
//! 布頂点バッファに中身が無く、1本目の刻みが来るまでの描画が未初期化の頂点を読むことになるためである。
//! 固定・アタッチ・掴みは目標拘束であり(`_doc/設計/XPBD共通拘束基盤.md`「判断6」)、動く目標(スキン済み頂点)は積分の後・反復の前の
//! 「目標の確定」でその刻みの値を目標位置バッファへ写す(判断8の工程2)。粒子の位置を直接書く別の工程は無い。
//! 拘束の工程は`constraint_stage`が持つ。
//! 参照: `_doc/設計/時間の規律.md`「判断5」「判断9」。

use super::collision_stage::空間ハッシュと分離を積む;
use super::constraint_stage::拘束を積む;
use super::dispatch::{self, 発行の指定};
use super::布ハンドル;
use crate::cloth_material::{布の彩色の区間, 布の彩色の色数上限, 布の拘束の反復回数, 布の自己衝突};
use crate::vulkan::frame::布描画入力;
use crate::vulkan::graph::{グラフ, バッファハンドル, バッファ用途};

/// 拘束の工程を除いて布が1刻みで積むコンピュートパスの本数(介入・積分・目標の確定・乗数零化・ハッシュ消去・格納・分離・仕上げ)。
/// 目標の確定を積まない布(更新対応0件)と自己衝突を行わない布ではこれより少ない。
const 拘束以外の一刻みのパス数: u32 = 8;

/// 布シミュレーションが1刻みで積むコンピュートパスの本数の上限。拘束の工程は(色の数 + 目標拘束の1色)×反復回数であり、色の数の上限で数える。
pub(crate) const 一刻みのパス数: u32 = 拘束以外の一刻みのパス数 + (布の彩色の色数上限 + 1) * 布の拘束の反復回数;

/// スキン済みハンドルは目標の確定のパスの読み宣言に使う(判断52の合流点)。
/// 更新対応0件の吊るし布(判断56)では目標の確定のパス自体を積まない(スキン済みハンドルも不要)。
pub(in crate::vulkan::frame::record) fn 積む<'a>(
    グラフ: &mut グラフ<'a>,
    入力: &'a 布描画入力,
    ハンドル: &布ハンドル,
    スキン済み: Option<バッファハンドル>,
) {
    for _ in 0..入力.進める刻み数.本数() {
        一刻みを積む(グラフ, 入力, ハンドル, スキン済み);
    }
    dispatch::積む(
        グラフ,
        入力,
        発行の指定 {
            名前: "布頂点生成",
            読み: vec![(ハンドル.粒子, バッファ用途::コンピュート読み)],
            書き: vec![(ハンドル.布頂点, バッファ用途::コンピュート書き)],
            pipeline: 入力.頂点生成pipeline,
            スレッド数: 入力.粒子数,
            色の区間: None,
        },
    );
}

/// 固定刻み1本ぶんの工程: 介入→積分→目標の確定→乗数零化→(拘束(色ごと)→目標拘束)×反復回数→(ハッシュ消去→格納→分離)→仕上げ。
/// 括弧の3本は自己衝突を行う布だけが積む。
fn 一刻みを積む<'a>(
    グラフ: &mut グラフ<'a>, 入力: &'a 布描画入力, ハンドル: &布ハンドル, スキン済み: Option<バッファハンドル>
) {
    let 粒 = (ハンドル.粒子, バッファ用途::コンピュート読み書き);
    let 前 = (ハンドル.前位置, バッファ用途::コンピュート読み書き);
    let 目標 = (ハンドル.目標位置, バッファ用途::コンピュート読み書き);
    dispatch::積む(グラフ, 入力, 点ごとの指定("布介入", vec![目標], 入力.介入pipeline, 入力.介入件数.max(1)));
    dispatch::積む(グラフ, 入力, 点ごとの指定("布積分", vec![粒, 前], 入力.積分pipeline, 入力.粒子数));
    if let (Some(スキン済み), 1..) = (スキン済み, 入力.目標の更新対応の件数) {
        dispatch::積む(
            グラフ,
            入力,
            発行の指定 {
                名前: "布目標の確定",
                読み: vec![
                    (スキン済み, バッファ用途::コンピュート読み),
                    (ハンドル.目標の更新対応, バッファ用途::コンピュート読み),
                ],
                書き: vec![目標],
                pipeline: 入力.目標の確定pipeline,
                スレッド数: 入力.目標の更新対応の件数,
                色の区間: Some(布の彩色の区間 {
                    開始: 0,
                    本数: 入力.目標の更新対応の件数,
                }),
            },
        );
    }
    拘束を積む(グラフ, 入力, ハンドル, 粒);
    if 入力.自己衝突 == 布の自己衝突::行う {
        空間ハッシュと分離を積む(グラフ, 入力, ハンドル, 粒);
    }
    dispatch::積む(
        グラフ,
        入力,
        発行の指定 {
            名前: "布仕上げ",
            読み: vec![(ハンドル.前位置, バッファ用途::コンピュート読み)],
            書き: vec![粒],
            pipeline: 入力.仕上げpipeline,
            スレッド数: 入力.粒子数,
            色の区間: None,
        },
    );
}

/// 粒子ごと(または介入ごと)に1スレッドを立て、読み宣言を持たない工程の指定。
fn 点ごとの指定(
    名前: &'static str,
    書き: Vec<(バッファハンドル, バッファ用途)>,
    pipeline: ash::vk::Pipeline,
    スレッド数: u32,
) -> 発行の指定 {
    発行の指定 {
        名前,
        読み: vec![],
        書き,
        pipeline,
        スレッド数,
        色の区間: None,
    }
}
