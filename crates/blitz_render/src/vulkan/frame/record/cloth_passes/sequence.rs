//! 布シミュレーションの依存順にコンピュートパスを積む。
//!
//! シミュレーションの工程はその描画で進める刻み数ぶん繰り返す。1描画に1回だけ積む形は、布の進む速さが画面の
//! 書き換え頻度に比例する欠陥(毎秒120回書き換えるモニターで2倍速、毎秒30回で半速)をそのまま残すためである。
//! 可変の巨大な刻み幅を1回で進める形は採らない(判断4と同じ理由に加え、位置ベースの拘束解決が大きな刻みで暴れる)。
//! 頂点生成だけは刻み数と無関係に描画機会ごとに1回積む。粒子から描画用の頂点を作り直す工程であって時間を1つも
//! 進めないため、時間意味の区分では「描画機会ごと」に属する。刻み0本の描画でもこれを積むのは、確保直後の
//! 布頂点バッファに中身が無く、1本目の刻みが来るまでの描画が未初期化の頂点を読むことになるためである。
//! 参照: `_doc/設計/時間の規律.md`「判断5」「判断9」。

use super::dispatch;
use super::布ハンドル;
use crate::vulkan::frame::布描画入力;
use crate::vulkan::graph::{グラフ, バッファハンドル, バッファ用途};

const セル総数: u32 = 32 * 32 * 32;

/// 布シミュレーションが1刻みで積むコンピュートパスの本数。アタッチを積まない吊るし布ではこれより1本少ない。
pub(crate) const 一刻みのパス数: u32 = 11;

/// スキン済みハンドルはアタッチパスの読み宣言に使う(判断52の合流点)。
/// アタッチ0件の吊るし布(判断56)ではアタッチパス自体を積まない(スキン済みハンドルも不要)。
pub(in crate::vulkan::frame::record) fn 積む<'a>(
    グラフ: &mut グラフ<'a>,
    入力: &'a 布描画入力,
    ハンドル: &布ハンドル,
    スキン済み: Option<バッファハンドル>,
) {
    for _ in 0..入力.進める刻み数.本数() {
        一刻みを積む(グラフ, 入力, ハンドル, スキン済み);
    }
    dispatch::積む(
        グラフ,
        "布頂点生成",
        vec![(ハンドル.粒子, バッファ用途::コンピュート読み)],
        vec![(ハンドル.布頂点, バッファ用途::コンピュート書き)],
        入力,
        入力.頂点生成pipeline,
        入力.粒子数,
    );
}

/// 固定刻み1本ぶんの工程: 介入→積分→アタッチ→拘束x4→ハッシュ消去→格納→分離→仕上げ。
fn 一刻みを積む<'a>(
    グラフ: &mut グラフ<'a>, 入力: &'a 布描画入力, ハンドル: &布ハンドル, スキン済み: Option<バッファハンドル>
) {
    let 粒 = (ハンドル.粒子, バッファ用途::コンピュート読み書き);
    let 前 = (ハンドル.前位置, バッファ用途::コンピュート読み書き);
    dispatch::積む(グラフ, "布介入", vec![], vec![粒, 前], 入力, 入力.介入pipeline, 入力.介入件数.max(1));
    dispatch::積む(グラフ, "布積分", vec![], vec![粒, 前], 入力, 入力.積分pipeline, 入力.粒子数);
    if let (Some(スキン済み), 1..) = (スキン済み, 入力.アタッチ件数) {
        dispatch::積む(
            グラフ,
            "布アタッチ",
            vec![(スキン済み, バッファ用途::コンピュート読み)],
            vec![粒, 前],
            入力,
            入力.アタッチpipeline,
            入力.アタッチ件数,
        );
    }
    for 名前 in ["布拘束1", "布拘束2", "布拘束3", "布拘束4"] {
        dispatch::積む(グラフ, 名前, vec![], vec![粒], 入力, 入力.拘束pipeline, 入力.粒子数);
    }
    空間ハッシュと分離を積む(グラフ, 入力, ハンドル, 粒);
}

/// 近傍探索の空間ハッシュを作り直し、粒子どうしの重なりを分離してから、この刻みの速度を確定する。
fn 空間ハッシュと分離を積む<'a>(
    グラフ: &mut グラフ<'a>,
    入力: &'a 布描画入力,
    ハンドル: &布ハンドル,
    粒: (バッファハンドル, バッファ用途),
) {
    dispatch::積む(
        グラフ,
        "布ハッシュ消去",
        vec![],
        vec![(ハンドル.セルカウント, バッファ用途::コンピュート書き)],
        入力,
        入力.ハッシュ消去pipeline,
        セル総数,
    );
    dispatch::積む(
        グラフ,
        "布ハッシュ格納",
        vec![(ハンドル.粒子, バッファ用途::コンピュート読み)],
        vec![
            (ハンドル.セルカウント, バッファ用途::コンピュート読み書き),
            (ハンドル.セル格納, バッファ用途::コンピュート書き),
        ],
        入力,
        入力.ハッシュ格納pipeline,
        入力.粒子数,
    );
    dispatch::積む(
        グラフ,
        "布分離",
        vec![
            (ハンドル.セルカウント, バッファ用途::コンピュート読み),
            (ハンドル.セル格納, バッファ用途::コンピュート読み),
        ],
        vec![粒],
        入力,
        入力.分離pipeline,
        入力.粒子数,
    );
    dispatch::積む(
        グラフ,
        "布仕上げ",
        vec![(ハンドル.前位置, バッファ用途::コンピュート読み)],
        vec![粒],
        入力,
        入力.仕上げpipeline,
        入力.粒子数,
    );
}
