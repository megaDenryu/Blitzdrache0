//! 布のXPBDの拘束の工程(判断8の工程6と7): 物理刻みの開始でラグランジュ乗数を零へ戻し、彩色の色ごとに1回のディスパッチと
//! 目標拘束の1回のディスパッチを反復回数だけ繰り返す。受け取るのは布の描画入力とハンドル、積むのは零化1本と(色の数 + 1)×反復回数の拘束である。
//! 同じ色のディスパッチが反復ごとに同じ拘束の乗数を読み継ぐため、乗数は刻みの間だけ累積する(判断5)。
//! 目標拘束の色を距離拘束の色の後ろに置くのは、各反復の最後に射影した拘束がその粒子の位置を決めるためであり、硬い接続(コンプライアンス0)の粒子は
//! 反復を終えるたびに目標の上に載る(旧アタッチが積分の後に位置を書いていたのと同じ見え方を、拘束として保つ)。
//! 目標拘束の乗数は距離拘束の乗数の後ろに続くため、零化の区間は両方の合計であり、目標拘束の区間の開始は距離拘束の数である。

use super::dispatch::{self, 発行の指定};
use super::布ハンドル;
use crate::cloth_material::{布の彩色の区間, 布の拘束の反復回数};
use crate::vulkan::frame::布描画入力;
use crate::vulkan::graph::{グラフ, バッファハンドル, バッファ用途};

/// 乗数を零へ戻してから、色ごとの拘束と目標拘束のディスパッチを反復回数だけ繰り返す。
pub(super) fn 拘束を積む<'a>(
    グラフ: &mut グラフ<'a>, 入力: &'a 布描画入力, ハンドル: &布ハンドル, 粒: (バッファハンドル, バッファ用途)
) {
    let 乗数 = (ハンドル.ラグランジュ乗数, バッファ用途::コンピュート読み書き);
    // 零化は距離拘束と目標拘束の全部を1つの区間として受ける(定数UBOの4語は粒子数・一辺・介入件数・目標拘束の数で埋まっている)。
    let 全拘束 = 布の彩色の区間 {
        開始: 0,
        本数: 入力.拘束の数 + 入力.目標拘束の数,
    };
    dispatch::積む(
        グラフ,
        入力,
        発行の指定 {
            名前: "布乗数零化",
            読み: vec![],
            書き: vec![(ハンドル.ラグランジュ乗数, バッファ用途::コンピュート書き)],
            pipeline: 入力.乗数零化pipeline,
            スレッド数: 全拘束.本数,
            色の区間: Some(全拘束),
        },
    );
    let 目標拘束の色 = 布の彩色の区間 {
        開始: 入力.拘束の数,
        本数: 入力.目標拘束の数,
    };
    for _ in 0..布の拘束の反復回数 {
        for 区間 in &入力.色の区間一覧 {
            dispatch::積む(
                グラフ,
                入力,
                発行の指定 {
                    名前: "布拘束",
                    読み: vec![(ハンドル.拘束の引数, バッファ用途::コンピュート読み)],
                    書き: vec![粒, 乗数],
                    pipeline: 入力.拘束pipeline,
                    スレッド数: 区間.本数,
                    色の区間: Some(*区間),
                },
            );
        }
        if 入力.目標拘束の数 > 0 {
            dispatch::積む(
                グラフ,
                入力,
                発行の指定 {
                    名前: "布目標拘束",
                    読み: vec![
                        (ハンドル.目標拘束の引数, バッファ用途::コンピュート読み),
                        (ハンドル.目標位置, バッファ用途::コンピュート読み),
                    ],
                    書き: vec![粒, 乗数],
                    pipeline: 入力.目標拘束pipeline,
                    スレッド数: 入力.目標拘束の数,
                    色の区間: Some(目標拘束の色),
                },
            );
        }
    }
}
