//! 布のXPBDの拘束の工程(判断8の工程6と7)と、衝突の後の目標拘束の最終の成立: 物理刻みの開始でラグランジュ乗数を零へ戻し、距離拘束の色ごとに1回、
//! 曲げ拘束の色ごとに1回、目標拘束の1回のディスパッチを反復回数だけ繰り返す。受け取るのは布の描画入力とハンドル、積むのは零化1本と
//! (距離の色の数 + 曲げの色の数 + 1)×反復回数の拘束、それに分離と床とカプセルの押し出しの後の目標拘束1本である。
//! 曲げ拘束を距離拘束の後ろ・目標拘束の前に置くのは、目標拘束を各反復の最後にする規則(下記)を保つためである。曲げは4粒子を触り、固定した粒子も動かすため、
//! 目標拘束の後ろに置くと固定が緩む。距離の前に置かないのは、伸びの補正が最後になると曲げの補正の残りが伸びに現れず、伸びの違反を距離の反復が消す既存の性質を保つためである(判断11)。
//! 同じ色のディスパッチが反復ごとに同じ拘束の乗数を読み継ぐため、乗数は刻みの間だけ累積する(判断5)。
//! 目標拘束の色を距離拘束の色の後ろに置くのは、各反復の最後に射影した拘束がその粒子の位置を決めるためであり、硬い接続(コンプライアンス0)の粒子は
//! 反復を終えるたびに目標の上に載る(旧アタッチが積分の後に位置を書いていたのと同じ見え方を、拘束として保つ)。
//! 最終の成立は同じシェーダーの同じ区間をもう1回積む。分離と押し出しが全粒子を動かすため、速度を作る前に目標拘束を成立させないと、
//! 近傍が重なった固定点・カプセルの内側や床の下に目標を持つ粒子が目標から外れたまま次の刻みへ誤った速度を持ち越す(判断6「目標拘束の最終の成立」)。
//! 乗数は反復の値を読み継いで最終の成立の分も足す(乗数=加えた補正の総量)。
//! 目標拘束の乗数は距離拘束の乗数の後ろに続くため、零化の区間は両方の合計であり、目標拘束の区間の開始は距離拘束の数である。

use super::dispatch::{self, 拘束の区間の指定, 発行の指定};
use super::布ハンドル;
use crate::cloth_material::{布の彩色の区間, 布の拘束の反復回数};
use crate::vulkan::frame::布描画入力;
use crate::vulkan::graph::{グラフ, バッファハンドル, バッファ用途};

/// 乗数を零へ戻してから、色ごとの距離拘束と色ごとの曲げ拘束と目標拘束のディスパッチを反復回数だけ繰り返す。
pub(super) fn 拘束を積む<'a>(
    グラフ: &mut グラフ<'a>, 入力: &'a 布描画入力, ハンドル: &布ハンドル, 粒: (バッファハンドル, バッファ用途)
) {
    let 乗数 = (ハンドル.ラグランジュ乗数, バッファ用途::コンピュート読み書き);
    // 零化は距離拘束と目標拘束と曲げ拘束の全部を1つの区間として受ける(定数UBOの4語は粒子数・一辺・介入件数・目標拘束の数で埋まっている)。
    let 全拘束 = 布の彩色の区間 {
        開始: 0,
        本数: 入力.拘束の数 + 入力.目標拘束の数 + 入力.曲げ拘束の数,
    };
    dispatch::積む(
        グラフ,
        入力,
        発行の指定 {
            名前: "布乗数零化",
            読み: vec![],
            書き: vec![(ハンドル.ラグランジュ乗数, バッファ用途::コンピュート書き)],
            pipeline: 入力.乗数零化pipeline,
            スレッド数: 全拘束.本数,
            色の区間: Some(拘束の区間の指定::色の区間から生成する(全拘束)),
        },
    );
    for _ in 0..布の拘束の反復回数 {
        for 区間 in &入力.色の区間一覧 {
            dispatch::積む(
                グラフ,
                入力,
                発行の指定 {
                    名前: "布拘束",
                    読み: vec![(ハンドル.拘束の引数, バッファ用途::コンピュート読み)],
                    書き: vec![粒, 乗数],
                    pipeline: 入力.拘束pipeline,
                    スレッド数: 区間.本数,
                    色の区間: Some(拘束の区間の指定::色の区間から生成する(*区間)),
                },
            );
        }
        for 区間 in &入力.曲げの色の区間一覧 {
            dispatch::積む(
                グラフ,
                入力,
                発行の指定 {
                    名前: "布曲げ拘束",
                    読み: vec![(ハンドル.曲げ拘束の引数, バッファ用途::コンピュート読み)],
                    書き: vec![粒, 乗数],
                    pipeline: 入力.曲げ拘束pipeline,
                    スレッド数: 区間.本数,
                    色の区間: Some(拘束の区間の指定 {
                        開始: 区間.開始,
                        本数: 区間.本数,
                        乗数の開始: 入力.拘束の数 + 入力.目標拘束の数,
                    }),
                },
            );
        }
        目標拘束を一回積む(グラフ, 入力, ハンドル, 粒, "布目標拘束");
    }
}

/// 分離と床とカプセルの押し出しの後、仕上げが速度を作る前に、目標拘束をもう1回射影して固定・アタッチ・掴みを最終の位置で成立させる。
pub(super) fn 目標拘束の最終の成立を積む<'a>(
    グラフ: &mut グラフ<'a>,
    入力: &'a 布描画入力,
    ハンドル: &布ハンドル,
    粒: (バッファハンドル, バッファ用途),
) {
    目標拘束を一回積む(グラフ, 入力, ハンドル, 粒, "布目標拘束の最終の成立");
}

/// 目標拘束のバッチ全体(彩色の1色)を1回射影する。目標拘束が0本の布には積まない。
fn 目標拘束を一回積む<'a>(
    グラフ: &mut グラフ<'a>,
    入力: &'a 布描画入力,
    ハンドル: &布ハンドル,
    粒: (バッファハンドル, バッファ用途),
    名前: &'static str,
) {
    if 入力.目標拘束の数 == 0 {
        return;
    }
    dispatch::積む(
        グラフ,
        入力,
        発行の指定 {
            名前,
            読み: vec![
                (ハンドル.目標拘束の引数, バッファ用途::コンピュート読み),
                (ハンドル.目標位置, バッファ用途::コンピュート読み),
            ],
            書き: vec![粒, (ハンドル.ラグランジュ乗数, バッファ用途::コンピュート読み書き)],
            pipeline: 入力.目標拘束pipeline,
            スレッド数: 入力.目標拘束の数,
            色の区間: Some(拘束の区間の指定::色の区間から生成する(布の彩色の区間 {
                開始: 入力.拘束の数,
                本数: 入力.目標拘束の数,
            })),
        },
    );
}
