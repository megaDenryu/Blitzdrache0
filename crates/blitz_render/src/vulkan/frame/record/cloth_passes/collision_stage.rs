//! 布の衝突の工程(判断8の工程5に当たる近傍探索と分離、および床とカプセルの押し出し)。受け取るのは布の描画入力とハンドル、
//! 積むのは自己衝突を行う布のハッシュ消去→格納→分離の3本と、全ての布の床とカプセルの押し出し1本である。
//! 自己衝突の3本はIssue #36の移行で中身を変えていない。CPUの参照計算と突き合わせる布は分離を再現できないため、3本を積まない(`布の自己衝突::行わない`)。
//! 押し出しは旧仕上げの前半であり、速度の再構成と分けたのは、その間に目標拘束の最終の成立を積むためである(`constraint_stage`)。

use super::dispatch::{self, 発行の指定};
use super::布ハンドル;
use crate::vulkan::frame::布描画入力;
use crate::vulkan::graph::{グラフ, バッファハンドル, バッファ用途};

const セル総数: u32 = 32 * 32 * 32;

/// 近傍探索の空間ハッシュを作り直し、粒子どうしの重なりを分離する。
pub(super) fn 空間ハッシュと分離を積む<'a>(
    グラフ: &mut グラフ<'a>,
    入力: &'a 布描画入力,
    ハンドル: &布ハンドル,
    粒: (バッファハンドル, バッファ用途),
) {
    dispatch::積む(
        グラフ,
        入力,
        発行の指定 {
            名前: "布ハッシュ消去",
            読み: vec![],
            書き: vec![(ハンドル.セルカウント, バッファ用途::コンピュート書き)],
            pipeline: 入力.ハッシュ消去pipeline,
            スレッド数: セル総数,
            色の区間: None,
        },
    );
    dispatch::積む(
        グラフ,
        入力,
        発行の指定 {
            名前: "布ハッシュ格納",
            読み: vec![(ハンドル.粒子, バッファ用途::コンピュート読み)],
            書き: vec![
                (ハンドル.セルカウント, バッファ用途::コンピュート読み書き),
                (ハンドル.セル格納, バッファ用途::コンピュート書き),
            ],
            pipeline: 入力.ハッシュ格納pipeline,
            スレッド数: 入力.粒子数,
            色の区間: None,
        },
    );
    dispatch::積む(
        グラフ,
        入力,
        発行の指定 {
            名前: "布分離",
            読み: vec![
                (ハンドル.セルカウント, バッファ用途::コンピュート読み),
                (ハンドル.セル格納, バッファ用途::コンピュート読み),
            ],
            書き: vec![粒],
            pipeline: 入力.分離pipeline,
            スレッド数: 入力.粒子数,
            色の区間: None,
        },
    );
}

/// 床(y=0)とカプセルの内側にある粒子を表面へ押し出す。位置だけを書く。
pub(super) fn 床とカプセルの押し出しを積む<'a>(
    グラフ: &mut グラフ<'a>, 入力: &'a 布描画入力, 粒: (バッファハンドル, バッファ用途)
) {
    dispatch::積む(
        グラフ,
        入力,
        発行の指定 {
            名前: "布床とカプセルの押し出し",
            読み: vec![],
            書き: vec![粒],
            pipeline: 入力.床とカプセルの押し出しpipeline,
            スレッド数: 入力.粒子数,
            色の区間: None,
        },
    );
}
