//! 拘束の工程が零化→(色ごと→目標拘束)×反復回数の並びで積まれることと、衝突の後に目標拘束の最終の成立が仕上げの前に積まれることの検証。材料は`test_fixtures`が持つ。

#![allow(clippy::unwrap_used)]

use super::test_fixtures::{
    刻み数を据えた入力, 検査の色の数, 目標拘束の数を据えた入力, 積んだパス名一覧, 自己衝突を選んで刻み数を据えた入力
};
use crate::cloth_material::{布の拘束の反復回数, 布の自己衝突};

/// 反証: 零化を反復の中で積むと、反復ごとに乗数が零へ戻って正典式の累積が消える。零化は1刻みに1本だけ、拘束の前に積む。
/// 拘束のディスパッチは色の数×反復回数であり、同じ色の並びを反復のたびに繰り返す。
#[test]
fn 拘束の工程は零化一本の後に色の数かける反復回数だけ積まれる() {
    let 名前一覧 = 積んだパス名一覧(&刻み数を据えた入力(1));
    let 零化の位置 = 名前一覧.iter().position(|名前| *名前 == "布乗数零化").unwrap();
    let 最初の拘束の位置 = 名前一覧.iter().position(|名前| *名前 == "布拘束").unwrap();
    assert!(零化の位置 < 最初の拘束の位置);
    assert_eq!(名前一覧.iter().filter(|名前| **名前 == "布乗数零化").count(), 1);
    assert_eq!(
        名前一覧.iter().filter(|名前| **名前 == "布拘束").count(),
        検査の色の数 * usize::try_from(布の拘束の反復回数).unwrap()
    );
    assert!(名前一覧.len() <= usize::try_from(super::一刻みのパス数).unwrap() + 1);
}

/// 反証: 目標拘束を反復の外に1回だけ積むと、距離拘束が反復のたびに固定の粒子を動かして固定が緩む。目標拘束は各反復の距離拘束の色の後ろに1回ずつ積む。
#[test]
fn 目標拘束は各反復の距離拘束の後ろに一本ずつ積まれ零本なら積まれない() {
    let 名前一覧 = 積んだパス名一覧(&刻み数を据えた入力(1));
    assert_eq!(
        名前一覧.iter().filter(|名前| **名前 == "布目標拘束").count(),
        usize::try_from(布の拘束の反復回数).unwrap()
    );
    let 位置一覧: Vec<usize> = 名前一覧
        .iter()
        .enumerate()
        .filter(|(_, 名前)| **名前 == "布目標拘束")
        .map(|(位置, _)| 位置)
        .collect();
    for 窓 in 位置一覧.windows(2) {
        assert_eq!(窓[1] - 窓[0], 検査の色の数 + 1);
    }
    assert_eq!(名前一覧[位置一覧[0] - 1], "布拘束");
    let 零本 = 積んだパス名一覧(&目標拘束の数を据えた入力(1, 0));
    assert!(!零本.contains(&"布目標拘束"));
}

/// 反証: 目標拘束の最終の成立を分離と押し出しの前に積む、あるいは積まないと、分離で押された固定点・床の下に目標を持つ粒子が目標から外れた位置で
/// 速度を作り、次の刻みへ誤った速度を持ち越す(参照比較のfloor条件でCPUと0.05メートル食い違った)。順は分離→押し出し→最終の成立→仕上げであり、
/// 最終の成立は1刻みに1本、目標拘束0本の布には積まない。
#[test]
fn 目標拘束の最終の成立は分離と押し出しの後で仕上げの前に一本だけ積まれる() {
    let 名前一覧 = 積んだパス名一覧(&刻み数を据えた入力(1));
    let 位置 = |名前: &str| 名前一覧.iter().position(|候補| *候補 == 名前).unwrap();
    assert_eq!(名前一覧.iter().filter(|名前| **名前 == "布目標拘束の最終の成立").count(), 1);
    assert!(位置("布分離") < 位置("布床とカプセルの押し出し"));
    assert_eq!(位置("布床とカプセルの押し出し") + 1, 位置("布目標拘束の最終の成立"));
    assert_eq!(位置("布目標拘束の最終の成立") + 1, 位置("布仕上げ"));
    assert!(名前一覧.iter().rposition(|名前| *名前 == "布目標拘束").unwrap() < 位置("布分離"));
    let 零本 = 積んだパス名一覧(&目標拘束の数を据えた入力(1, 0));
    assert!(!零本.contains(&"布目標拘束の最終の成立"));
    assert_eq!(
        零本.iter().position(|名前| *名前 == "布床とカプセルの押し出し").unwrap() + 1,
        零本.iter().position(|名前| *名前 == "布仕上げ").unwrap()
    );
}

/// 反証: 自己衝突を行わない布にも分離を積むと、CPUの参照計算が再現できない工程がGPUの結果へ混ざる。押し出しと仕上げは両方が積む。
#[test]
fn 自己衝突を行わない布は空間ハッシュと分離を積まず仕上げは積む() {
    let 名前一覧 = 積んだパス名一覧(&自己衝突を選んで刻み数を据えた入力(1, 布の自己衝突::行わない));
    assert!(!名前一覧.iter().any(|名前| ["布ハッシュ消去", "布ハッシュ格納", "布分離"].contains(名前)));
    assert_eq!(名前一覧.iter().filter(|名前| **名前 == "布床とカプセルの押し出し").count(), 1);
    assert_eq!(名前一覧.iter().filter(|名前| **名前 == "布仕上げ").count(), 1);
    let 行う = 積んだパス名一覧(&自己衝突を選んで刻み数を据えた入力(1, 布の自己衝突::行う));
    assert_eq!(行う.len(), 名前一覧.len() + 3);
}
