//! 光のにじみ拡大チェーンのパス宣言(判断41)。1段小さい解像度の拡大結果(最下段では縮小最終段)を
//! 3x3テントで広げ、同解像度の縮小結果へ加算して拡大[段]へ書く。

use ash::vk;

use super::fullscreen_draw;
use crate::vulkan::frame::光のにじみ描画入力;
use crate::vulkan::graph::{カラー添付列, パス宣言, パス種別, 画像ハンドル, 画像用途};

/// 前提: 添字は段番号。長さはピラミッドの段数上限-1と一致させる。
const 拡大パス名一覧: [&str; 4] = ["光のにじみ拡大1", "光のにじみ拡大2", "光のにじみ拡大3", "光のにじみ拡大4"];

pub(super) fn 光のにじみ拡大パスを宣言する<'a>(
    段: usize,
    小さい方: 画像ハンドル,
    基準: 画像ハンドル,
    書き: 画像ハンドル,
    入力: &'a 光のにじみ描画入力,
    寸法: vk::Extent2D,
) -> パス宣言<'a> {
    let set = 入力.拡大set一覧[段];
    let (pipeline, layout) = (入力.拡大pipeline, 入力.拡大layout);
    パス宣言::生成する(
        拡大パス名一覧[段],
        vec![(小さい方, 画像用途::シェーダー読み画素段), (基準, 画像用途::シェーダー読み画素段)],
        vec![(書き, 画像用途::カラー出力)],
        Vec::new(),
        Vec::new(),
        パス種別::グラフィックス {
            カラー: カラー添付列::色だけ(書き),
            深度: None,
            クリア指定: fullscreen_draw::黒クリア(),
        },
        move |文脈| {
            fullscreen_draw::コマンドを積む(文脈.device(), 文脈.コマンドバッファ(), pipeline, layout, set, 寸法, None);
        },
    )
}
