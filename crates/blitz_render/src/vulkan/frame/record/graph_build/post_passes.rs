//! ポストプロセスパス列の積み込み(判断41): 時間再構成 → 自動露出(消去→集計→導出と適応) → 前処理(HDR→縮小0) →
//! 縮小チェーン → 拡大チェーン(下から加算) → 明るさの圧縮(HDR+光のにじみ最終→スワップチェーン)。
//! この順序自体が担当する関心事であり、各パスの中身は`temporal_reconstruction_pass`・`auto_exposure_passes`・
//! `bloom_down_pass`・`bloom_up_pass`・`tonemap_pass`が持つ。
//!
//! 時間再構成を先頭へ置くのは光のにじみとの順序が理由である。画素より細かいハイライトの明滅を再構成より前に
//! 光のにじみへ通すと、その明滅が増幅されて画面全体へ広がる。副次的に、集計より前に再構成が入ると
//! フレームごとの輝度分布の揺れが減り、露出の追従が落ち着く(`参照: _doc/設計/時間再構成.md`「判断d」)。
//!
//! 自動露出を光のにじみより前へ置くのは、Nフレームのヒストグラムを同じNフレームの絵へ効かせるためである。
//! 集計と光のにじみの前処理はどちらもHDR中間画像を読むだけであり、順を入れ替えても絵は変わらない。
//! 明るさの圧縮だけが、更新した露出状態と完成した光のにじみの両方を待つ。

use ash::vk;

use super::super::{auto_exposure_passes, bloom_down_pass, bloom_up_pass, tonemap_pass};
use super::base_images::基本画像ハンドル;
use super::post_setup::ポスト構成;
use super::stages;
use crate::vulkan::graph;
use crate::vulkan::temporal_reconstruction::{合成入力の注入入力, 時間再構成描画入力};

pub(super) fn ポストプロセスパス列を積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    構成: &ポスト構成<'a>,
    基本: &基本画像ハンドル,
    時間再構成: Option<&'a 時間再構成描画入力>,
    合成入力: Option<合成入力の注入入力>,
    寸法: vk::Extent2D,
) {
    stages::時間再構成を積む(グラフ, 構成.hdrハンドル, 基本, 時間再構成, 合成入力, 寸法);
    if let Some(自動露出) = &構成.自動露出 {
        グラフ.パスを積む(auto_exposure_passes::ヒストグラム消去パスを宣言する(自動露出.ヒストグラム));
        グラフ.パスを積む(auto_exposure_passes::hdr集計パスを宣言する(
            構成.hdrハンドル,
            自動露出.ヒストグラム,
            自動露出.入力,
            寸法,
        ));
        グラフ.パスを積む(auto_exposure_passes::露出導出と適応パスを宣言する(
            自動露出.ヒストグラム,
            自動露出.露出状態,
            自動露出.入力,
        ));
    }
    let 段数 = 構成.縮小ハンドル一覧.len();
    グラフ.パスを積む(bloom_down_pass::光のにじみ前処理パスを宣言する(
        構成.hdrハンドル,
        構成.縮小ハンドル一覧[0],
        構成.光のにじみ,
        構成.寸法一覧[0],
    ));
    for 段 in 1..段数 {
        グラフ.パスを積む(bloom_down_pass::光のにじみ縮小段パスを宣言する(
            段,
            構成.縮小ハンドル一覧[段 - 1],
            構成.縮小ハンドル一覧[段],
            構成.光のにじみ,
            構成.寸法一覧[段],
        ));
    }
    for 段 in (0..段数.saturating_sub(1)).rev() {
        let 小さい方 = if 段 + 1 < 段数 - 1 {
            構成.拡大ハンドル一覧[段 + 1]
        } else {
            構成.縮小ハンドル一覧[段数 - 1]
        };
        グラフ.パスを積む(bloom_up_pass::光のにじみ拡大パスを宣言する(
            段,
            小さい方,
            構成.縮小ハンドル一覧[段],
            構成.拡大ハンドル一覧[段],
            構成.光のにじみ,
            構成.寸法一覧[段],
        ));
    }
    グラフ.パスを積む(tonemap_pass::明るさの圧縮パスを宣言する(
        構成.hdrハンドル,
        構成.光のにじみ最終ハンドル(),
        基本.スワップチェーン,
        構成.自動露出.as_ref().map(|自動露出| 自動露出.露出状態),
        構成.明るさの圧縮,
        寸法,
    ));
}
