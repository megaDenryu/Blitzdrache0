//! ポストプロセスパス列の積み込み(判断41): 前処理(HDR→縮小0) → 縮小チェーン →
//! 拡大チェーン(下から加算) → トーンマップ(HDR+ブルーム最終→スワップチェーン)。
//! `graph_build`の行数分割のためだけに切り出した内部ヘルパー。

use ash::vk;

use super::super::{bloom_down_pass, bloom_up_pass, tonemap_pass};
use super::post_setup::ポスト構成;
use crate::vulkan::graph;

pub(super) fn 積む<'a>(
    グラフ: &mut graph::グラフ<'a>, 構成: &ポスト構成<'a>, スワップチェーン: graph::画像ハンドル, 寸法: vk::Extent2D
) {
    let 段数 = 構成.縮小ハンドル一覧.len();
    グラフ.パスを積む(bloom_down_pass::前処理を作る(
        構成.hdrハンドル,
        構成.縮小ハンドル一覧[0],
        構成.ブルーム,
        構成.寸法一覧[0],
    ));
    for 段 in 1..段数 {
        グラフ.パスを積む(bloom_down_pass::縮小を作る(
            段,
            構成.縮小ハンドル一覧[段 - 1],
            構成.縮小ハンドル一覧[段],
            構成.ブルーム,
            構成.寸法一覧[段],
        ));
    }
    for 段 in (0..段数.saturating_sub(1)).rev() {
        let 小さい方 = if 段 + 1 < 段数 - 1 {
            構成.拡大ハンドル一覧[段 + 1]
        } else {
            構成.縮小ハンドル一覧[段数 - 1]
        };
        グラフ.パスを積む(bloom_up_pass::作る(
            段,
            小さい方,
            構成.縮小ハンドル一覧[段],
            構成.拡大ハンドル一覧[段],
            構成.ブルーム,
            構成.寸法一覧[段],
        ));
    }
    グラフ.パスを積む(tonemap_pass::作る(
        構成.hdrハンドル,
        構成.ブルーム最終ハンドル(),
        スワップチェーン,
        構成.トーンマップ,
        寸法,
    ));
}
