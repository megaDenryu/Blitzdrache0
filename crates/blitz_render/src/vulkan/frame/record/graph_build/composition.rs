//! engineが宣言したフレーム段階列を順に展開する。

use ash::vk;

use super::{base_images, post_passes, post_setup, readback_stage, stages};
use crate::clear_color::クリアカラー;
use crate::frame_composition::{フレーム構成, フレーム段階};
use crate::vulkan::frame::record::ui_pass;
use crate::vulkan::frame::{フレーム画像一式, 任意描画入力, 描画対象入力, 描画方式};
use crate::vulkan::graph;

/// 段階列の展開の結果。計器へ渡す数だけを返す。
pub(super) struct 積み上げの実績 {
    /// このフレームで積んだ大気のベイク済み画像生成パスの本数。
    pub(super) 大気のベイク済み画像生成パス数: u32,
    /// このフレームで積んだ間接照明の表現の生成パスの本数の内訳。
    pub(super) 間接照明生成パス数: crate::distant_environment::間接照明生成パス数,
}

#[allow(clippy::too_many_arguments)]
pub(super) fn フレーム段階列を展開して積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    構成: &フレーム構成,
    画像一式: &フレーム画像一式<'_>,
    基本: &base_images::基本画像ハンドル,
    ポスト: Option<&post_setup::ポスト構成<'a>>,
    カラー: graph::画像ハンドル,
    クリア色: クリアカラー,
    描画対象: 描画対象入力<'a>,
    任意: 任意描画入力<'a>,
    描画方式: &'a 描画方式,
    寸法: vk::Extent2D,
) -> 積み上げの実績 {
    // 大気のベイク済み画像の生成はフレームの先頭へ積む。ベイク済み画像を読む段階(空・空中遠近)より必ず前に置くためであり、レンダーグラフが宣言順に実行することでこの前後関係が保たれる。焼き直さないフレームでは1本も積まれない。
    let 大気のベイク済み画像 = stages::大気のベイク済み画像を積む(
        グラフ,
        任意.大気のベイク済み画像,
        stages::空パスがベイク済み画像を参照するか(任意.空),
        任意.空中遠近合成.is_some(),
    );
    // 間接照明の表現は大気のベイク済み画像の後ろへ積む。遠方環境用スカイビューの生成が透過率と多重散乱を読むためであり、レンダーグラフが宣言順に実行することでこの前後関係が保たれる。焼き直さないフレームは1本も積まないが、消費側が読む3枚は登録する。
    let 間接照明 = stages::間接照明を積む(グラフ, 任意.間接照明, 大気のベイク済み画像.経路の二枚);
    let mut スキン済み = None;
    let mut 布 = None;
    // 読み戻しの段階がシーンの段階より後ろに宣言されているため、そこで転送元に選べる局所可視度のハンドルはここで受け取って運ぶ。
    let mut 局所可視度 = None;
    for 段階 in 構成.段階一覧() {
        match 段階 {
            フレーム段階::スキニング => スキン済み = stages::スキニングを積む(グラフ, 任意.スキニング),
            フレーム段階::布シミュレーション => 布 = stages::布を積む(グラフ, 任意.布, スキン済み),
            フレーム段階::影 => {
                // 全キャスターを外した対照では布も積まない。パスそのものは積むため消去と保存は起こる。
                let 影の布 = 描画対象.影のキャスター.影へ積むか().then_some(布).flatten();
                stages::影を積む(
                    グラフ,
                    基本,
                    &画像一式.シャドウマップ距離区分別のビュー一覧,
                    スキン済み,
                    影の布,
                    描画対象.距離区分別のシャドウ,
                    描画対象.共有,
                );
                // 点光源の影を同じ段階の中で多段影の後ろへ積む。影段階が影の資源を作る唯一の段階であり、
                // 別の段階を新設するとフレーム構成をエンジン側で動かすことになるためである。
                stages::点光源の影を積む(
                    グラフ,
                    基本,
                    画像一式.点光源の影の層別のビュー一覧,
                    描画対象.点光源の影の計画,
                    描画対象.点光源の影の束縛,
                    描画対象.点光源の影の発行,
                    描画対象.共有,
                );
            }
            フレーム段階::シーン => {
                局所可視度 = stages::シーンを積む(グラフ, 基本, カラー, スキン済み, 布, クリア色, 描画対象, 間接照明.消費画像, 任意, 寸法);
            }
            フレーム段階::空 => {
                stages::空を積む(グラフ, 基本, カラー, 任意.空, 任意.空中遠近合成, 大気のベイク済み画像.読み先, 寸法);
            }
            フレーム段階::粒子 => stages::粒子を積む(グラフ, 基本, カラー, 任意.粒子, 寸法),
            フレーム段階::光のにじみと明るさの圧縮 => {
                let ポスト = ポスト.unwrap_or_else(|| panic!("フレーム構成にポスト処理があるが資源が無い"));
                post_passes::ポストプロセスパス列を積む(グラフ, ポスト, 基本, 任意.時間再構成, 任意.時間再構成の合成入力, 寸法);
            }
            フレーム段階::UI => {
                if let Some(入力) = 任意.ui {
                    グラフ.パスを積む(ui_pass::ui描画パスを宣言する(基本.スワップチェーン, 入力, 寸法));
                }
            }
            フレーム段階::読み戻し => readback_stage::読み戻しを積む(グラフ, 描画方式, 基本, ポスト, 局所可視度, 寸法),
        }
    }
    積み上げの実績 {
        大気のベイク済み画像生成パス数: 大気のベイク済み画像.生成パス数,
        間接照明生成パス数: 間接照明.生成パス数,
    }
}
