//! ポストプロセス画像(HDR・ブルームピラミッド全段)のグラフ登録(判断38・41)。
//! `graph_build`の行数分割のためだけに切り出した内部ヘルパー。

use ash::vk;

use crate::vulkan::frame::{トーンマップ描画入力, ブルーム描画入力, フレーム画像一式};
use crate::vulkan::graph;

pub(super) struct ポスト構成<'a> {
    pub(super) hdrハンドル: graph::画像ハンドル,
    pub(super) 縮小ハンドル一覧: Vec<graph::画像ハンドル>,
    pub(super) 拡大ハンドル一覧: Vec<graph::画像ハンドル>,
    pub(super) 寸法一覧: Vec<vk::Extent2D>,
    pub(super) トーンマップ: &'a トーンマップ描画入力,
    pub(super) ブルーム: &'a ブルーム描画入力,
}

impl ポスト構成<'_> {
    /// トーンマップが読むブルームの最終結果。2段以上なら拡大チェーンの最上段、1段のみなら縮小結果。
    pub(super) fn ブルーム最終ハンドル(&self) -> graph::画像ハンドル {
        self.拡大ハンドル一覧.first().copied().unwrap_or(self.縮小ハンドル一覧[0])
    }
}

/// 前提: ポストプロセスの入力2つと画像はレンダラーが対で生成する(不一致は配線のバグ)。
/// ピラミッド各段の初期状態はHDRと同じ「前フレームの最後はフラグメント読み」
/// (縮小段は拡大パスの基準読み、拡大段は1段上の拡大パスまたはトーンマップの読み)のため同じ初期状態関数を使う。
pub(super) fn 登録する<'a>(
    グラフ: &mut graph::グラフ<'a>,
    画像一式: &フレーム画像一式,
    トーンマップ入力: Option<&'a トーンマップ描画入力>,
    ブルーム入力: Option<&'a ブルーム描画入力>,
    寸法: vk::Extent2D,
) -> Option<ポスト構成<'a>> {
    match (トーンマップ入力, ブルーム入力, 画像一式.hdr, &画像一式.ブルーム) {
        (Some(トーンマップ), Some(ブルーム), Some((hdr画像, hdrビュー)), Some(ブルーム画像)) => {
            let hdrハンドル = 登録(グラフ, hdr画像, hdrビュー, 寸法);
            let 縮小ハンドル一覧 = ブルーム画像
                .縮小一覧
                .iter()
                .zip(&ブルーム画像.寸法一覧)
                .map(|(&(画像, ビュー), &段寸法)| 登録(グラフ, 画像, ビュー, 段寸法))
                .collect();
            let 拡大ハンドル一覧 = ブルーム画像
                .拡大一覧
                .iter()
                .zip(&ブルーム画像.寸法一覧)
                .map(|(&(画像, ビュー), &段寸法)| 登録(グラフ, 画像, ビュー, 段寸法))
                .collect();
            Some(ポスト構成 {
                hdrハンドル,
                縮小ハンドル一覧,
                拡大ハンドル一覧,
                寸法一覧: ブルーム画像.寸法一覧.clone(),
                トーンマップ,
                ブルーム,
            })
        }
        (None, None, None, None) => None,
        _ => panic!("ポストプロセスの入力と画像の有無が一致しない(レンダラーの配線のバグ)"),
    }
}

fn 登録(グラフ: &mut graph::グラフ<'_>, 画像: vk::Image, ビュー: vk::ImageView, 寸法: vk::Extent2D) -> graph::画像ハンドル {
    グラフ.画像を登録する(画像, ビュー, graph::画像アスペクト::カラー, graph::前フレームhdr読み直後状態(), 寸法)
}
