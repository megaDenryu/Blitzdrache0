//! ポストプロセス画像(HDR・光のにじみピラミッド全段)のグラフ登録(判断38・41)。
//! 登録して得たハンドルを`ポスト構成`にまとめ、パス積み込み(`post_passes`)へ渡す。

use ash::vk;

use crate::vulkan::auto_exposure::自動露出描画入力;
use crate::vulkan::frame::{フレーム画像一式, 光のにじみ描画入力, 明るさの圧縮描画入力};
use crate::vulkan::graph;

/// ポストプロセスの登録済みハンドル一式。
///
/// `自動露出`は露出方式がヒストグラム自動の世界だけ`Some`であり、入力と2本のバッファハンドルは同時に
/// 有ることも無いこともある。
pub(super) struct ポスト構成<'a> {
    pub(super) hdrハンドル: graph::画像ハンドル,
    pub(super) 縮小ハンドル一覧: Vec<graph::画像ハンドル>,
    pub(super) 拡大ハンドル一覧: Vec<graph::画像ハンドル>,
    pub(super) 寸法一覧: Vec<vk::Extent2D>,
    pub(super) 明るさの圧縮: &'a 明るさの圧縮描画入力,
    pub(super) 光のにじみ: &'a 光のにじみ描画入力,
    pub(super) 自動露出: Option<自動露出の登録<'a>>,
}

/// 自動露出のパスが読み書きする2本のバッファのハンドルと、そのフレームの入力。
pub(super) struct 自動露出の登録<'a> {
    pub(super) 入力: &'a 自動露出描画入力,
    pub(super) ヒストグラム: graph::バッファハンドル,
    pub(super) 露出状態: graph::バッファハンドル,
}

impl ポスト構成<'_> {
    /// 明るさの圧縮が読む光のにじみの最終結果。2段以上なら拡大チェーンの最上段、1段のみなら縮小結果。
    pub(super) fn 光のにじみ最終ハンドル(&self) -> graph::画像ハンドル {
        self.拡大ハンドル一覧.first().copied().unwrap_or(self.縮小ハンドル一覧[0])
    }
}

/// 前提: ポストプロセスの入力2つと画像はレンダラーが対で生成する(不一致は配線のバグ)。
/// ピラミッド各段の初期状態はHDRと同じ「前フレームの最後は画素段読み」
/// (縮小段は拡大パスの基準読み、拡大段は1段上の拡大パスまたは明るさの圧縮の読み)のため同じ初期状態関数を使う。
pub(super) fn 登録する<'a>(
    グラフ: &mut graph::グラフ<'a>,
    画像一式: &フレーム画像一式<'_>,
    明るさの圧縮入力: Option<&'a 明るさの圧縮描画入力>,
    光のにじみ入力: Option<&'a 光のにじみ描画入力>,
    自動露出入力: Option<&'a 自動露出描画入力>,
    寸法: vk::Extent2D,
) -> Option<ポスト構成<'a>> {
    match (明るさの圧縮入力, 光のにじみ入力, 画像一式.hdr, &画像一式.光のにじみ) {
        (Some(明るさの圧縮), Some(光のにじみ), Some((hdr画像, hdrビュー)), Some(光のにじみ画像)) => {
            let hdrハンドル = 登録(グラフ, hdr画像, hdrビュー, 寸法);
            let 縮小ハンドル一覧 = 光のにじみ画像
                .縮小一覧
                .iter()
                .zip(&光のにじみ画像.寸法一覧)
                .map(|(&(画像, ビュー), &段寸法)| 登録(グラフ, 画像, ビュー, 段寸法))
                .collect();
            let 拡大ハンドル一覧 = 光のにじみ画像
                .拡大一覧
                .iter()
                .zip(&光のにじみ画像.寸法一覧)
                .map(|(&(画像, ビュー), &段寸法)| 登録(グラフ, 画像, ビュー, 段寸法))
                .collect();
            Some(ポスト構成 {
                自動露出: 自動露出入力.map(|入力| 自動露出の登録 {
                    入力,
                    // ヒストグラムはこのフレームの消去で0へ戻すが、前フレームの最後の読みとのWARハザードを宣言するため初期状態を持つ。
                    ヒストグラム: グラフ.バッファを登録する(入力.ヒストグラムバッファ, graph::前フレームコンピュート読み直後状態()),
                    露出状態: グラフ.バッファを登録する(入力.露出状態バッファ, graph::前フレーム画素段読み直後状態()),
                }),
                hdrハンドル,
                縮小ハンドル一覧,
                拡大ハンドル一覧,
                寸法一覧: 光のにじみ画像.寸法一覧.clone(),
                明るさの圧縮,
                光のにじみ,
            })
        }
        (None, None, None, None) => None,
        _ => panic!("ポストプロセスの入力と画像の有無が一致しない(レンダラーの配線のバグ)"),
    }
}

fn 登録(グラフ: &mut graph::グラフ<'_>, 画像: vk::Image, ビュー: vk::ImageView, 寸法: vk::Extent2D) -> graph::画像ハンドル {
    グラフ.画像を登録する(画像, ビュー, graph::画像アスペクト::カラー, graph::前フレームhdr読み直後状態(), 寸法)
}
