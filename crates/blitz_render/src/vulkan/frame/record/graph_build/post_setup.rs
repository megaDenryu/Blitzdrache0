//! ポストプロセス画像(HDR・ブルームa/b)のグラフ登録(判断38・39)。
//! `graph_build`の行数分割のためだけに切り出した内部ヘルパー。

use ash::vk;

use crate::vulkan::frame::{トーンマップ描画入力, ブルーム描画入力, フレーム画像一式};
use crate::vulkan::graph;

pub(super) struct ポスト構成<'a> {
    pub(super) hdrハンドル: graph::画像ハンドル,
    pub(super) aハンドル: graph::画像ハンドル,
    pub(super) bハンドル: graph::画像ハンドル,
    pub(super) 半解像度: vk::Extent2D,
    pub(super) トーンマップ: &'a トーンマップ描画入力,
    pub(super) ブルーム: &'a ブルーム描画入力,
}

/// 前提: ポストプロセスの入力2つと画像2組はレンダラーが対で生成する(不一致は配線のバグ)。
/// a・bの初期状態もHDRと同じ「前フレームの最後はフラグメント読み」
/// (aはトーンマップ、bは縦ぼかしが最後の読み手)のため同じ初期状態関数を使う。
pub(super) fn 登録する<'a>(
    グラフ: &mut graph::グラフ<'a>,
    画像一式: &フレーム画像一式,
    トーンマップ入力: Option<&'a トーンマップ描画入力>,
    ブルーム入力: Option<&'a ブルーム描画入力>,
    寸法: vk::Extent2D,
) -> Option<ポスト構成<'a>> {
    match (トーンマップ入力, ブルーム入力, 画像一式.hdr, 画像一式.ブルーム) {
        (Some(トーンマップ), Some(ブルーム), Some((hdr画像, hdrビュー)), Some(ブルーム画像)) => {
            let hdrハンドル = グラフ.画像を登録する(
                hdr画像,
                hdrビュー,
                graph::画像アスペクト::カラー,
                graph::前フレームhdr読み直後状態(),
                寸法,
            );
            let aハンドル = グラフ.画像を登録する(
                ブルーム画像.a画像,
                ブルーム画像.aビュー,
                graph::画像アスペクト::カラー,
                graph::前フレームhdr読み直後状態(),
                ブルーム画像.寸法,
            );
            let bハンドル = グラフ.画像を登録する(
                ブルーム画像.b画像,
                ブルーム画像.bビュー,
                graph::画像アスペクト::カラー,
                graph::前フレームhdr読み直後状態(),
                ブルーム画像.寸法,
            );
            Some(ポスト構成 {
                hdrハンドル,
                aハンドル,
                bハンドル,
                半解像度: ブルーム画像.寸法,
                トーンマップ,
                ブルーム,
            })
        }
        (None, None, None, None) => None,
        _ => panic!("ポストプロセスの入力と画像の有無が一致しない(レンダラーの配線のバグ)"),
    }
}
