//! 読み戻しコピーの転送元を選んでグラフへ積む工程。受け取るのは描画方式とスワップチェーン・ポスト構成、返すものは無い。
//!
//! 転送元の選択をここが所有するのは、対象がスワップチェーンと圧縮前のHDR中間画像で分かれ、HDRのときだけ終端で休むレイアウトへ戻す宣言が要るためである。
//!
//! 注意: HDR中間画像はグラフの外で毎フレーム使い回し、次フレームの初期状態を「明るさの圧縮パスの画素段読みの直後」と決めてある
//! (`graph/initial_state.rs`の`前フレームhdr読み直後状態`)。転送元のまま終わらせると、次フレームのシーン描画のカラー書きが
//! 前フレームの転送読みを跨ぐ危険を宣言できなくなるため、読み戻した後に画素段読みへ戻す終端宣言を必ず添える。
//! 深度画像も同じ理由で終端宣言が要る。次フレームの初期状態は「深度書き込みの直後」と決めてあるためである
//! (`graph/initial_state.rs`の`前フレーム深度書き込み直後状態`)。動きベクトル画像も同じ理由で終端宣言が要る。
//! 次フレームの初期状態は「カラー添付への書き込みの直後」と決めてあるためである
//! (`graph/initial_state/temporal_reconstruction.rs`)。局所可視度の画像も同じ理由で終端宣言が要る。
//! 休むレイアウトをGENERALに固定してあり、転送元のまま終わらせるとその不変条件が破れる
//! (`graph/initial_state/local_visibility.rs`)。

use ash::vk;

use super::base_images::基本画像ハンドル;
use super::post_setup::ポスト構成;
use crate::vulkan::frame::record::readback_pass;
use crate::vulkan::frame::描画方式;
use crate::vulkan::graph;
use crate::vulkan::readback::読み戻し対象;

pub(super) fn 積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    描画方式: &描画方式,
    基本: &基本画像ハンドル,
    ポスト: Option<&ポスト構成<'a>>,
    局所可視度: Option<graph::画像ハンドル>,
    寸法: vk::Extent2D,
) {
    let 描画方式::読み戻し { バッファ, 対象 } = 描画方式 else {
        return;
    };
    match 対象 {
        読み戻し対象::提示画像 => グラフ.パスを積む(readback_pass::作る(基本.スワップチェーン, *バッファ, *対象, 寸法)),
        読み戻し対象::圧縮前のHDR => {
            let 構成 = ポスト.unwrap_or_else(|| panic!("圧縮前のHDRの読み戻しを要求されたがポスト処理の資源が無い"));
            グラフ.パスを積む(readback_pass::作る(構成.hdrハンドル, *バッファ, *対象, 寸法));
            グラフ.最終用途を宣言する(構成.hdrハンドル, graph::画像用途::シェーダー読み画素段);
        }
        読み戻し対象::最終深度 => {
            グラフ.パスを積む(readback_pass::作る(基本.深度, *バッファ, *対象, 寸法));
            グラフ.最終用途を宣言する(基本.深度, graph::画像用途::深度出力);
        }
        読み戻し対象::動きベクトル => {
            グラフ.パスを積む(readback_pass::作る(基本.動きベクトル, *バッファ, *対象, 寸法));
            グラフ.最終用途を宣言する(基本.動きベクトル, graph::画像用途::カラー出力);
        }
        読み戻し対象::局所可視度 => {
            let ハンドル =
                局所可視度.unwrap_or_else(|| panic!("局所可視度の読み戻しを要求されたが、そのフレームは局所可視性補正のパスを1本も積んでいない"));
            グラフ.パスを積む(readback_pass::作る(ハンドル, *バッファ, *対象, 寸法));
            グラフ.最終用途を宣言する(ハンドル, graph::画像用途::焼いた画像の画素段参照);
        }
    }
}
