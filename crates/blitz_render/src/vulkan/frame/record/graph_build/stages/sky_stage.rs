//! 空段階をレンダーグラフのパスへ展開する。担当する工程は「方式に応じて読み画像を決め、空中遠近合成と空の2本を
//! この順で積む」ことである。受け取るのはグラフと2つの描画入力と大気のベイク済み画像の読み先、返り値は無い。
//!
//! 合成を空より前に置くのは、合成が塗るのがジオメトリの画素、空が塗るのが背景の画素であり、合成が読む深度を
//! 空パスが深度アタッチメントとして束縛するためである。順が逆だと合成の深度読みが空の深度出力を待つ形になり、
//! 同じ深度画像を読みと書きで往復させる並びになる。
//!
//! 読み画像の用途に`焼いた画像の画素段参照`を使うのは、大気のベイク済み画像が休むレイアウトをGENERALに保つ不変条件が
//! あるためであり、通常の`シェーダー読み画素段`を使ってはならない
//! (参照: `graph/initial_state/atmosphere_lut.rs`)。

use ash::vk;

use super::super::base_images::基本画像ハンドル;
use super::atmosphere_lut_stage::{大気のベイク済み画像読みハンドル, 空段階の読み先};
use crate::vulkan::frame::record::{aerial_composite_pass, sky_pass};
use crate::vulkan::frame::{空中遠近合成描画入力, 空描画入力};
use crate::vulkan::graph;

/// 空パスが大気のベイク済み画像を参照するか。空パスを積むフレームは必ず参照するため、そのフレームで焼かなくてもベイク済み画像を
/// グラフへ登録する必要がある。
pub(in crate::vulkan::frame::record::graph_build) fn 空パスがベイク済み画像を参照するか(入力: Option<&空描画入力>) -> bool {
    入力.is_some()
}

pub(in crate::vulkan::frame::record::graph_build) fn 空を積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    基本: &基本画像ハンドル,
    カラー: graph::画像ハンドル,
    入力: Option<&'a 空描画入力>,
    合成入力: Option<&'a 空中遠近合成描画入力>,
    読み先: 空段階の読み先,
    寸法: vk::Extent2D,
) {
    // 合成パスとそれが読むボリュームは同じ1つの条件(合成があるか)から決まるため、対で取り出す。
    if let Some((合成入力, 空中遠近)) = 合成入力.zip(読み先.合成のボリューム) {
        グラフ.パスを積む(aerial_composite_pass::作る(カラー, 基本.深度, 空中遠近, 合成入力, 寸法));
    }
    if let Some(入力) = 入力 {
        let 読み画像 = 読み画像を決める(読み先.空パスの二枚);
        グラフ.パスを積む(sky_pass::作る(カラー, 基本.深度, 読み画像, 入力, 寸法));
    }
}

/// 空パスが読む2枚のベイク済み画像。
///
/// ハンドルが無いのは、空段階があるのに大気のベイク済み画像資源が無いという到達しない状態である
/// (どちらもフレーム構成の空段階の有無だけで決まり、レンダラーの入力検査が食い違いを先に落とす)。
fn 読み画像を決める(
    読みハンドル: Option<大気のベイク済み画像読みハンドル>
) -> Vec<(graph::画像ハンドル, graph::画像用途)> {
    let ハンドル = 読みハンドル.unwrap_or_else(|| panic!("空パスがあるのに大気のベイク済み画像がグラフへ登録されていない"));
    vec![
        (ハンドル.透過率, graph::画像用途::焼いた画像の画素段参照),
        (ハンドル.スカイビュー, graph::画像用途::焼いた画像の画素段参照),
    ]
}
