//! 条件依存の3枚(透過率・多重散乱・スカイビュー)の積み方を、焼く組の腕ごとに決める工程。
//! 受け取るのはグラフとそのフレームの描画入力、返すのは3枚のハンドルと積んだ本数である。
//!
//! 腕ごとに登録の仕方が違うのは、焼く画像と引くだけの画像で初期状態が違うためである。3枚をまとめて持つのは、
//! 後段のLUTが前段のLUTを読む依存が3枚の内側だけで閉じており、腕をまたいでハンドルの出どころを揃える必要があるためである。

use super::register::{二枚を読む, 引く画像を登録する, 焼く画像を登録する, 生成パスを積む};
use super::大気LUT読みハンドル;

use crate::vulkan::atmosphere_lut::{大気LUT描画入力, 大気LUT生成入力, 生成する組};
use crate::vulkan::graph;

/// 3枚を積んだ結果。空中遠近が読む2枚のハンドルも返すのは、焼いたか引くだけかで初期状態が違うためである。
pub(super) struct 三枚の積み上げ {
    pub(super) 読みハンドル: Option<大気LUT読みハンドル>,
    pub(super) 透過率: graph::画像ハンドル,
    pub(super) 多重散乱: graph::画像ハンドル,
    pub(super) 生成パス数: u32,
}

pub(super) fn 条件依存の三枚を積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    入力: &'a 大気LUT描画入力,
    空パスが引くか: bool,
) -> 三枚の積み上げ {
    match &入力.焼く組 {
        生成する組::何も焼かない => 三枚とも引くだけ(グラフ, 入力, 空パスが引くか),
        生成する組::スカイビューだけ {
            スカイビュー: スカイビュー入力,
        } => スカイビューだけ焼く(グラフ, 入力, スカイビュー入力),
        生成する組::全部 {
            透過率: 透過率入力,
            多重散乱: 多重散乱入力,
            スカイビュー: スカイビュー入力,
        } => 三枚とも焼く(グラフ, 入力, [透過率入力, 多重散乱入力, スカイビュー入力]),
    }
}

fn 三枚とも引くだけ<'a>(
    グラフ: &mut graph::グラフ<'a>, 入力: &'a 大気LUT描画入力, 空パスが引くか: bool
) -> 三枚の積み上げ {
    let 透過率 = 引く画像を登録する(グラフ, &入力.透過率画像);
    let 多重散乱 = 引く画像を登録する(グラフ, &入力.多重散乱画像);
    let スカイビュー = 引く画像を登録する(グラフ, &入力.スカイビュー画像);
    三枚の積み上げ {
        読みハンドル: 空パスが引くか.then_some(大気LUT読みハンドル {
            透過率, スカイビュー
        }),
        透過率,
        多重散乱,
        生成パス数: 0,
    }
}

fn スカイビューだけ焼く<'a>(
    グラフ: &mut graph::グラフ<'a>,
    入力: &'a 大気LUT描画入力,
    スカイビュー入力: &'a 大気LUT生成入力,
) -> 三枚の積み上げ {
    let 透過率 = 引く画像を登録する(グラフ, &入力.透過率画像);
    let 多重散乱 = 引く画像を登録する(グラフ, &入力.多重散乱画像);
    let スカイビュー = 焼く画像を登録する(グラフ, &入力.スカイビュー画像);
    生成パスを積む(グラフ, "スカイビュー生成", スカイビュー, 二枚を読む(透過率, 多重散乱), スカイビュー入力);
    三枚の積み上げ {
        読みハンドル: Some(大気LUT読みハンドル {
            透過率, スカイビュー
        }),
        透過率,
        多重散乱,
        生成パス数: 1,
    }
}

fn 三枚とも焼く<'a>(
    グラフ: &mut graph::グラフ<'a>, 入力: &'a 大気LUT描画入力, 三枚の入力: [&'a 大気LUT生成入力; 3]
) -> 三枚の積み上げ {
    let [透過率入力, 多重散乱入力, スカイビュー入力] = 三枚の入力;
    let 透過率 = 焼く画像を登録する(グラフ, &入力.透過率画像);
    let 多重散乱 = 焼く画像を登録する(グラフ, &入力.多重散乱画像);
    let スカイビュー = 焼く画像を登録する(グラフ, &入力.スカイビュー画像);
    生成パスを積む(グラフ, "透過率生成", 透過率, Vec::new(), 透過率入力);
    生成パスを積む(
        グラフ,
        "多重散乱生成",
        多重散乱,
        vec![(透過率, graph::画像用途::コンピュート読み)],
        多重散乱入力,
    );
    生成パスを積む(グラフ, "スカイビュー生成", スカイビュー, 二枚を読む(透過率, 多重散乱), スカイビュー入力);
    三枚の積み上げ {
        読みハンドル: Some(大気LUT読みハンドル {
            透過率, スカイビュー
        }),
        透過率,
        多重散乱,
        生成パス数: 3,
    }
}
