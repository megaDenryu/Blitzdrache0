//! 間接照明の画像をレンダーグラフへ登録する工程。受け取るのはグラフとそのフレームの描画入力、返すのは
//! 標準PBRと布が参照する3枚のハンドルである。パスは1本も積まない。
//!
//! 初期状態の選び方をここが1箇所で持つのは、それが画像ごとでなくそのフレームでの扱いで決まるためである。
//! 焼き直す画像はレイアウトをUNDEFINEDから始めて中身を捨て、参照するだけの画像はGENERALのまま中身を保つ。
//! 拡散照度と鏡面畳込みは遠方環境と一緒に焼き直され、反射率積分表だけが起動後の1回で焼き終わるため、
//! 同じフレームに2つの扱いが混ざる(参照: `crates/blitz_render/src/vulkan/graph/initial_state/baked_image.rs`)。

use crate::vulkan::graph;
use crate::vulkan::indirect_lighting::{登録する画像, 間接照明の描画入力, 間接照明の焼く組};

/// 標準PBRと布の画素段が参照する3枚のハンドル。
#[derive(Clone, Copy)]
pub(in crate::vulkan::frame::record::graph_build) struct 遠方環境の消費画像 {
    拡散照度: graph::画像ハンドル,
    鏡面畳込み: graph::画像ハンドル,
    反射率積分表: graph::画像ハンドル,
}

impl 遠方環境の消費画像 {
    /// シーン描画の読み画像の宣言へそのまま足せる並び。3枚とも画素段からサンプラーで読む。
    pub(in crate::vulkan::frame::record::graph_build) fn 読み宣言(self) -> [(graph::画像ハンドル, graph::画像用途); 3] {
        let 用途 = graph::画像用途::焼いた画像の画素段参照;
        [(self.拡散照度, 用途), (self.鏡面畳込み, 用途), (self.反射率積分表, 用途)]
    }

    pub(super) fn 鏡面畳込み(self) -> graph::画像ハンドル {
        self.鏡面畳込み
    }

    pub(super) fn 拡散照度(self) -> graph::画像ハンドル {
        self.拡散照度
    }

    pub(super) fn 反射率積分表(self) -> graph::画像ハンドル {
        self.反射率積分表
    }
}

pub(super) fn 消費する画像を登録する(
    グラフ: &mut graph::グラフ<'_>, 入力: &間接照明の描画入力
) -> 遠方環境の消費画像 {
    let 派生を焼くか = matches!(入力.焼く組, 間接照明の焼く組::焼く { .. });
    遠方環境の消費画像 {
        拡散照度: 登録する(グラフ, &入力.拡散照度の画像, 派生を焼くか),
        鏡面畳込み: 登録する(グラフ, &入力.鏡面畳込みの画像, 派生を焼くか),
        反射率積分表: 登録する(グラフ, &入力.反射率積分表の画像, 入力.反射率積分表の入力.is_some()),
    }
}

/// 遠方環境の立方体画像。派生表現を焼くときだけの中間であり、標準PBRが読まないため焼くフレームだけ登録する。
pub(super) fn 遠方環境を登録する(グラフ: &mut graph::グラフ<'_>, 画像: &登録する画像) -> graph::画像ハンドル {
    登録する(グラフ, 画像, true)
}

fn 登録する(グラフ: &mut graph::グラフ<'_>, 画像: &登録する画像, 焼き直すか: bool) -> graph::画像ハンドル {
    let 初期状態 = if 焼き直すか {
        graph::焼いた画像を焼き直すときの初期状態()
    } else {
        graph::焼いた画像を参照するだけのときの初期状態()
    };
    グラフ.画像を登録する(画像.画像, 画像.ビュー, graph::画像アスペクト::カラー, 初期状態, 画像.寸法)
}
