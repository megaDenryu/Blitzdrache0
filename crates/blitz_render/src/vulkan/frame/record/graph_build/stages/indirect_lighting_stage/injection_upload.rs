//! 検収が与える解析入力を、標準PBRが読む3枚へ転送で書き込む工程。受け取るのはグラフとそのフレームの描画入力と
//! 登録済みのハンドル、返すのは無しである。注入の無いフレームは1本も積まない。
//!
//! 焼き上げの積み上げと分けるのは、担当する工程が違うためである。あちらは大気から焼いた結果を段の順に導き、
//! こちらはホストが決めた値をそのまま載せる。注入があるフレームは計画が「何も焼かない」に固定されるため、
//! この2つが同じフレームで同時に走ることはない。

use super::graph_images::遠方環境の消費画像;
use crate::vulkan::derived_environment::copy_pass;
use crate::vulkan::graph;
use crate::vulkan::indirect_lighting::間接照明の描画入力;

/// 検収が与える解析入力を3枚へ転送で書き込む。生成パスではないため`間接照明生成パス数`には数えない
/// (この3本が積まれるフレームは計画が「何も焼かない」であり、生成パスは1本も無い)。
pub(super) fn 注入を積む<'a>(
    グラフ: &mut graph::グラフ<'a>, 入力: &'a 間接照明の描画入力, 消費画像: 遠方環境の消費画像
) {
    let Some(注入) = &入力.注入 else {
        return;
    };
    グラフ.パスを積む(copy_pass::全段の書き込みパスを作る(
        "検収の拡散照度の注入",
        消費画像.拡散照度(),
        vec![注入.拡散照度の範囲],
        注入.層数,
        注入.拡散照度の元,
    ));
    グラフ.パスを積む(copy_pass::全段の書き込みパスを作る(
        "検収の鏡面畳込みの注入",
        消費画像.鏡面畳込み(),
        注入.鏡面畳込みの段ごとの範囲.clone(),
        注入.層数,
        注入.鏡面畳込みの元,
    ));
    グラフ.パスを積む(copy_pass::表の書き込みパスを作る(
        "検収の反射率積分表の注入",
        消費画像.反射率積分表(),
        注入.反射率積分表の範囲,
        注入.反射率積分表の元,
        copy_pass::二成分テクセルのバイト数,
    ));
}
