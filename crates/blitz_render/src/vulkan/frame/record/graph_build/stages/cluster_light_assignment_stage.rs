//! クラスタの選別の段階を展開する工程。受け取るのはそのフレームの選別の入力、返す代わりに2本のバッファを
//! 登録して選別のパスをグラフへ1本積む。
//!
//! 積むかどうかの判断を持たないのは、全世界がクラスタの経路を通るためである。局所光が0件の世界も件数0のセルだけを
//! 持つ格子を作り、画素段はその格子を読む(参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断f」)。
//!
//! 注意: 呼び出し元はこの工程をシーン描画より前へ置く。後ろへ置くと、そのフレームのシーン描画と布描画が
//! 前フレームの割り当てを読む。

use super::super::super::cluster_light_assignment_pass;
use crate::vulkan::cluster_light_assignment::クラスタ選別の描画入力;
use crate::vulkan::graph;

/// 画素段が読む2本のハンドル。呼び出し元がこの2本をシーン描画の読み宣言へ渡すことで、選別の書き込みと
/// 画素段の読みの間にバリアが立つ。返さずに済ませると、同じフレームの中で書きながら読む競合になる。
pub(in crate::vulkan::frame::record::graph_build) fn クラスタの選別を積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    入力: クラスタ選別の描画入力,
) -> [graph::バッファハンドル; 2] {
    let 格子 = 登録する(グラフ, 入力.格子);
    let 光添字列 = 登録する(グラフ, 入力.光添字列);
    グラフ.パスを積む(cluster_light_assignment_pass::作る(格子, 光添字列, 入力));
    [格子, 光添字列]
}

/// 前フレームの最後の用途は画素段のストレージ読みである。同じスロットのバッファをそのフレームの選別が
/// 上書きするため、書き込みとの間の順序をこの初期状態が表す。
fn 登録する(グラフ: &mut graph::グラフ<'_>, バッファ: ash::vk::Buffer) -> graph::バッファハンドル {
    グラフ.バッファを登録する(バッファ, graph::前フレーム画素段読み直後状態())
}
