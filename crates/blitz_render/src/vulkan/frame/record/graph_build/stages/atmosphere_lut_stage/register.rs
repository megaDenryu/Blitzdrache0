//! 大気LUT画像をグラフへ登録する工程。受け取るのはグラフとLUT1枚の画像としての姿、返すのはそのハンドルである。
//!
//! 「このフレームで焼く画像」と「引くだけの画像」で初期状態を分けるのが担当であり、どちらを選ぶかは呼び出し元が決める。
//! 選択を誤ると、焼き直さないフレームの内容が捨てられて空の色が跳ぶ
//! (参照: `crates/blitz_render/src/vulkan/graph/initial_state/atmosphere_lut.rs`)。

use crate::vulkan::atmosphere_lut::大気LUT画像入力;
use crate::vulkan::graph;

/// このフレームで全テクセルを焼き直す画像として登録する。内容を保たないためレイアウトはUNDEFINEDから始める。
pub(super) fn 焼く画像を登録する(グラフ: &mut graph::グラフ<'_>, 画像: &大気LUT画像入力) -> graph::画像ハンドル {
    登録する(グラフ, 画像, graph::大気lutを焼く画像の初期状態())
}

/// このフレームでは引くだけの画像として登録する。前フレームが焼いた内容を保つためGENERALから始める。
pub(super) fn 引く画像を登録する(グラフ: &mut graph::グラフ<'_>, 画像: &大気LUT画像入力) -> graph::画像ハンドル {
    登録する(グラフ, 画像, graph::大気lutを引く画像の初期状態())
}

fn 登録する(
    グラフ: &mut graph::グラフ<'_>, 画像: &大気LUT画像入力, 初期状態: graph::画像状態
) -> graph::画像ハンドル {
    グラフ.画像を登録する(画像.画像, 画像.ビュー, graph::画像アスペクト::カラー, 初期状態, 画像.寸法)
}
