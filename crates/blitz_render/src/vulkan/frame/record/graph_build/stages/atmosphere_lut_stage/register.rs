//! 大気のベイク済み画像の画像と生成パスをグラフへ登録する工程。受け取るのはグラフとベイク済み画像1枚の姿または1本のパスの材料、
//! 返すのは画像のハンドル(パスは戻り値を持たない)である。
//!
//! 「このフレームで焼く画像」と「参照するだけの画像」で初期状態を分けるのが担当であり、どちらを選ぶかは呼び出し元が決める。
//! 選択を誤ると、焼き直さないフレームの内容が捨てられて空の色が跳ぶ
//! (参照: `crates/blitz_render/src/vulkan/graph/initial_state/atmosphere_lut.rs`)。

use crate::vulkan::atmosphere_lut::pass as atmosphere_lut_pass;
use crate::vulkan::atmosphere_lut::{大気のベイク済み画像の生成入力, 大気のベイク済み画像の画像入力};
use crate::vulkan::graph;

/// このフレームで全テクセルを焼き直す画像として登録する。内容を保たないためレイアウトはUNDEFINEDから始める。
pub(super) fn 焼く画像を登録する(
    グラフ: &mut graph::グラフ<'_>, 画像: &大気のベイク済み画像の画像入力
) -> graph::画像ハンドル {
    登録する(グラフ, 画像, graph::焼いた画像を焼き直すときの初期状態())
}

/// このフレームでは参照するだけの画像として登録する。前フレームが焼いた内容を保つためGENERALから始める。
pub(super) fn 参照する画像を登録する(
    グラフ: &mut graph::グラフ<'_>, 画像: &大気のベイク済み画像の画像入力
) -> graph::画像ハンドル {
    登録する(グラフ, 画像, graph::焼いた画像を参照するだけのときの初期状態())
}

/// 生成パス1本を宣言する。名前はGPU計器の区間名そのままであり、報告の表にこの語で並ぶ。
pub(super) fn 生成パスを積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    パス名: &'static str,
    書き先: graph::画像ハンドル,
    読み画像: Vec<(graph::画像ハンドル, graph::画像用途)>,
    入力: &'a 大気のベイク済み画像の生成入力,
) {
    グラフ.パスを積む(atmosphere_lut_pass::作る(パス名, 書き先, 読み画像, 入力));
}

/// 透過率と多重散乱をコンピュート読みとして宣言する組。経路を刻む2つのパスがどちらもこの2枚を読む。
pub(super) fn 二枚を読む(
    透過率: graph::画像ハンドル, 多重散乱: graph::画像ハンドル
) -> Vec<(graph::画像ハンドル, graph::画像用途)> {
    vec![(透過率, graph::画像用途::コンピュート読み), (多重散乱, graph::画像用途::コンピュート読み)]
}

fn 登録する(
    グラフ: &mut graph::グラフ<'_>, 画像: &大気のベイク済み画像の画像入力, 初期状態: graph::画像状態
) -> graph::画像ハンドル {
    グラフ.画像を登録する(
        画像.画像,
        画像.ビュー,
        graph::画像アスペクト::カラー,
        初期状態,
        画像.形.グラフへ渡す寸法(),
    )
}
