//! 大気LUTの生成をレンダーグラフの具体的なパスへ展開する。担当する工程は「そのフレームで焼く組と、空パスがLUTを引くかどうかに応じて、画像を登録し生成パスを宣言順に積む」ことである。受け取るのはグラフとそのフレームのLUT生成入力、返すのは空パスへ渡す読み先のハンドルと、積んだ生成パスの本数である。
//!
//! 焼かないフレームでも画像を登録しうるのは、大気LUT腕の空パスが焼かないフレームでもLUTを引くためである。画像の登録は`register`が担う。

mod register;

use register::{引く画像を登録する, 焼く画像を登録する};

use crate::vulkan::atmosphere_lut::pass as atmosphere_lut_pass;
use crate::vulkan::atmosphere_lut::{大気LUT描画入力, 生成する組};
use crate::vulkan::graph;

/// 空パスが引く2枚のLUTのハンドル。多重散乱を含めないのは、引く側が経路を刻まないためである。
#[derive(Clone, Copy)]
pub(in crate::vulkan::frame::record::graph_build) struct 大気LUT読みハンドル {
    pub(in crate::vulkan::frame::record::graph_build) 透過率: graph::画像ハンドル,
    pub(in crate::vulkan::frame::record::graph_build) スカイビュー: graph::画像ハンドル,
}

/// 大気LUTの積み上げの結果。読み先のハンドルは、空パスがLUTを引くフレームでだけ値を持つ。
pub(in crate::vulkan::frame::record::graph_build) struct 大気LUT積み上げ結果 {
    pub(in crate::vulkan::frame::record::graph_build) 読みハンドル: Option<大気LUT読みハンドル>,
    /// このフレームで積んだ生成パスの本数。0・1・3のいずれかであり、計器がこの値を数える。
    pub(in crate::vulkan::frame::record::graph_build) 生成パス数: u32,
}

/// 大気LUTの生成を積む。宣言順を透過率→多重散乱→スカイビューに固定するのは、後段のLUTが前段のLUTを読むためである。
/// レンダーグラフは宣言順に実行してバリアだけを導くため、この順序を依存解析に任せない
/// (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「大気LUT方式の設計(第7段で実装する)」)。
pub(in crate::vulkan::frame::record::graph_build) fn 大気lutを積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    入力: Option<&'a 大気LUT描画入力>,
    空パスが引くか: bool,
) -> 大気LUT積み上げ結果 {
    let Some(入力) = 入力 else {
        return 大気LUT積み上げ結果 {
            読みハンドル: None,
            生成パス数: 0,
        };
    };
    match &入力.焼く組 {
        生成する組::何も焼かない => 大気LUT積み上げ結果 {
            読みハンドル: 空パスが引くか.then(|| 引くだけを登録する(グラフ, 入力)),
            生成パス数: 0,
        },
        生成する組::スカイビューだけ { スカイビュー } => {
            let 透過率 = 引く画像を登録する(グラフ, &入力.透過率画像);
            let 多重散乱 = 引く画像を登録する(グラフ, &入力.多重散乱画像);
            let 書き先 = 焼く画像を登録する(グラフ, &入力.スカイビュー画像);
            スカイビューを積む(グラフ, 書き先, 透過率, 多重散乱, スカイビュー);
            大気LUT積み上げ結果 {
                読みハンドル: Some(大気LUT読みハンドル {
                    透過率,
                    スカイビュー: 書き先,
                }),
                生成パス数: 1,
            }
        }
        生成する組::全部 {
            透過率: 透過率入力,
            多重散乱: 多重散乱入力,
            スカイビュー,
        } => {
            let 透過率 = 焼く画像を登録する(グラフ, &入力.透過率画像);
            let 多重散乱 = 焼く画像を登録する(グラフ, &入力.多重散乱画像);
            let スカイビュー画像 = 焼く画像を登録する(グラフ, &入力.スカイビュー画像);
            グラフ.パスを積む(atmosphere_lut_pass::作る("透過率生成", 透過率, Vec::new(), 透過率入力));
            let 透過率を読む = vec![(透過率, graph::画像用途::コンピュート読み)];
            グラフ.パスを積む(atmosphere_lut_pass::作る("多重散乱生成", 多重散乱, 透過率を読む, 多重散乱入力));
            スカイビューを積む(グラフ, スカイビュー画像, 透過率, 多重散乱, スカイビュー);
            大気LUT積み上げ結果 {
                読みハンドル: Some(大気LUT読みハンドル {
                    透過率,
                    スカイビュー: スカイビュー画像,
                }),
                生成パス数: 3,
            }
        }
    }
}

/// 生成パスを1本も積まないフレームで、空パスが引く2枚だけを登録する。
fn 引くだけを登録する(グラフ: &mut graph::グラフ<'_>, 入力: &大気LUT描画入力) -> 大気LUT読みハンドル {
    大気LUT読みハンドル {
        透過率: 引く画像を登録する(グラフ, &入力.透過率画像),
        スカイビュー: 引く画像を登録する(グラフ, &入力.スカイビュー画像),
    }
}

fn スカイビューを積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    書き先: graph::画像ハンドル,
    透過率: graph::画像ハンドル,
    多重散乱: graph::画像ハンドル,
    入力: &'a crate::vulkan::atmosphere_lut::大気LUT生成入力,
) {
    let 二枚を読む = vec![(透過率, graph::画像用途::コンピュート読み), (多重散乱, graph::画像用途::コンピュート読み)];
    グラフ.パスを積む(atmosphere_lut_pass::作る("スカイビュー生成", 書き先, 二枚を読む, 入力));
}
