//! シーン段階を展開する工程。深度プリパスを積み、その深度を読む局所可視性補正の2本を積み、続いて本体のシーン描画を1本積む。
//! 検収が合成深度を据えた実行では、プリパスと局所可視性補正の間へ深度を書き戻す転送を1本挟む。
//!
//! 段階の中の4種類のパスを1つの工程が持つのは、この順そのものが担当する関心事だからである。プリパスを外へ出すと、
//! 「深度を書く側」と「その深度を読んで可視度を焼く側」が別の呼び出し元に分かれ、順序の不変条件を1箇所で読めなくなる。
//! 合成深度の注入も同じ理由でここに置く。プリパスより前へ出ればプリパスに上書きされ、遮蔽の標本化より後ろへ出れば
//! 本番のジオメトリの深度が読まれる。局所可視性補正の書き込みとシーン描画の画素段の読みが対であることも同じである。

use ash::vk;

use super::super::base_images::基本画像ハンドル;
use super::indirect_lighting_stage::遠方環境の消費画像;
use super::{cluster_light_assignment_stage, depth_prepass_stage, local_visibility_stage};
use crate::clear_color::クリアカラー;
use crate::vulkan::depth_injection;
use crate::vulkan::frame::record::scene_pass;
use crate::vulkan::frame::{任意描画入力, 描画対象入力};
use crate::vulkan::graph;
use crate::vulkan::graph::クリア指定;

/// 局所可視性補正を積んだフレームだけ、両側ぼかしが書いた画像のハンドルを返す。読み戻しの段階がこの画像を転送元に選べるのは、
/// 同じグラフの中で状態を追われているハンドルを受け取ったときだけである。同じ画像をもう一度登録すると2本の状態の追跡が並び、
/// バリアがどちらの側の履歴からも導けなくなる。
#[allow(clippy::too_many_arguments)]
pub(in crate::vulkan::frame::record::graph_build) fn シーンを積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    基本: &基本画像ハンドル,
    カラー: graph::画像ハンドル,
    スキン済み: Option<graph::バッファハンドル>,
    布: Option<scene_pass::布ドロー<'a>>,
    クリア色: クリアカラー,
    描画対象: 描画対象入力<'a>,
    遠方環境: Option<遠方環境の消費画像>,
    任意: 任意描画入力<'a>,
    寸法: vk::Extent2D,
) -> Option<graph::画像ハンドル> {
    // 選別を段階の先頭へ置く。シーン描画と布描画がその結果を画素段で読むため、この順が保たれることで
    // 書き込みと読みの間にバリアが立つ。
    let クラスタの読み = cluster_light_assignment_stage::クラスタの選別を積む(グラフ, 描画対象.クラスタ選別);
    let 方式 = 描画対象.深度プリパス方式;
    depth_prepass_stage::深度プリパスを積む(グラフ, 基本, スキン済み, 描画対象, 方式, 寸法);
    if let Some(注入) = 任意.合成深度の注入 {
        グラフ.パスを積む(depth_injection::合成深度の注入を作る(基本.深度, 注入));
    }
    let 局所可視度 = local_visibility_stage::局所可視性を積む(グラフ, 基本.深度, 任意.局所可視性, 寸法);
    let mut 読み画像一覧 = vec![(基本.シャドウマップ, graph::画像用途::深度シェーダー読み)];
    if let Some(遠方環境) = 遠方環境 {
        読み画像一覧.extend(遠方環境.読み宣言());
    }
    // 局所可視性補正を積まないフレームは、その画像を書くパスが1本も無いためハンドルも無い。読み宣言も立てない。
    if let Some(局所可視度) = 局所可視度 {
        読み画像一覧.push((局所可視度, graph::画像用途::焼いた画像の画素段参照));
    }
    // 深度プリパスが書いた深度を消去せずに読み込む。両方が消去すると、等値の比較で1画素も描かれなくなる。
    let クリア = if 方式.深度プリパスを積むか() {
        クリア指定::カラーだけを消去して深度は読み込む { カラー: クリア色 }
    } else {
        クリア指定::クリアする { カラー: クリア色 }
    };
    グラフ.パスを積む(scene_pass::作る(
        カラー,
        基本.動きベクトル,
        基本.深度,
        読み画像一覧,
        スキン済み,
        布,
        クリア,
        描画対象.ジオメトリ,
        描画対象.共有,
        クラスタの読み,
        寸法,
    ));
    局所可視度
}
