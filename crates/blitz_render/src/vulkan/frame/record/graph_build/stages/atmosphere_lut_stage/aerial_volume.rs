//! 空中遠近ボリュームの積み方を決める工程。受け取るのはグラフとそのフレームの描画入力と前段2枚のハンドル、
//! 返すのはボリュームのハンドルと積んだ本数である。3枚の平面を`three_planes`が持つのと同じ分け方である。
//!
//! 引く条件が3枚と違うため別に分かれる。3枚は生成指示だけを条件にするのに対し、ボリュームは合成パスが
//! 在ることも条件に持ち、依存する先も透過率と多重散乱の2枚だけでスカイビューを含まない。

use super::register::{二枚を読む, 引く画像を登録する, 焼く画像を登録する, 生成パスを積む};

use crate::vulkan::atmosphere_lut::大気LUT描画入力;
use crate::vulkan::graph;

/// 空中遠近の積み上げの結果。ハンドルが値を持つことと、合成パスがボリュームを引くことは同じである。
pub(super) struct 空中遠近の積み上げ {
    pub(super) ハンドル: Option<graph::画像ハンドル>,
    pub(super) 生成パス数: u32,
}

/// 宣言順でスカイビューの後ろへ置くのは設計正本の固定順に従うためであり、依存の上ではスカイビューの結果を
/// 読まないため前後どちらでも成り立つ。
///
/// 焼かないフレームでも引くなら画像を登録するのは、登録が無いとバリアが導かれないためである。引かないフレーム
/// (`--no-aerial-composite`で合成を切った構成)では焼く入力も無く、画像を1枚も登録しない。
pub(super) fn 空中遠近を積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    入力: &'a 大気LUT描画入力,
    透過率: graph::画像ハンドル,
    多重散乱: graph::画像ハンドル,
    合成が引くか: bool,
) -> 空中遠近の積み上げ {
    if !合成が引くか {
        return 空中遠近の積み上げ {
            ハンドル: None,
            生成パス数: 0,
        };
    }
    let Some(空中遠近入力) = &入力.空中遠近 else {
        return 空中遠近の積み上げ {
            ハンドル: Some(引く画像を登録する(グラフ, &入力.空中遠近画像)),
            生成パス数: 0,
        };
    };
    let 書き先 = 焼く画像を登録する(グラフ, &入力.空中遠近画像);
    生成パスを積む(グラフ, "空中遠近生成", 書き先, 二枚を読む(透過率, 多重散乱), 空中遠近入力);
    空中遠近の積み上げ {
        ハンドル: Some(書き先),
        生成パス数: 1,
    }
}
