//! 時間再構成の段階を展開する工程。受け取るのは再構成後の色の書き先と基本画像のハンドルとそのフレームの入力、
//! 返す代わりに、世界が履歴混合を宣言したときだけパスを1本グラフへ積む。
//!
//! 積むかどうかの判断をここが持たないのは、入力の有無がその判断そのものだからである。方式が使わないの世界と
//! ポスト処理を組まない構成では入力が`None`であり、そのとき基本画像の登録も`None`になっている。
//!
//! 注意: 呼び出し元はこの工程をポストプロセスの段階の先頭へ置く。後ろへ置くと、光のにじみと自動露出の集計が
//! 再構成前の色を読む(`参照: _doc/設計/時間再構成.md`「判断d: 時間再構成パスの挿入位置」)。

use ash::vk;

use super::super::super::temporal_reconstruction_pass;
use super::super::base_images::基本画像ハンドル;
use crate::vulkan::graph;
use crate::vulkan::temporal_reconstruction::{
    合成入力の書き戻し先, 合成入力の注入を作る, 合成入力の注入入力, 時間再構成描画入力
};

/// 入力と画像の登録は必ず対で有るか対で無い。片方だけが有る状態はレンダラーの配線の誤りである。
#[allow(clippy::too_many_arguments)]
pub(in crate::vulkan::frame::record::graph_build) fn 時間再構成を積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    再構成後の色: graph::画像ハンドル,
    基本: &基本画像ハンドル,
    入力: Option<&'a 時間再構成描画入力>,
    合成入力: Option<合成入力の注入入力>,
    寸法: vk::Extent2D,
) {
    match (入力, &基本.時間再構成) {
        (Some(入力), Some(登録)) => {
            合成入力を積む(グラフ, 基本, 登録, 合成入力);
            let ハンドル = temporal_reconstruction_pass::時間再構成のハンドル組 {
                今のフレームの色: 登録.今のフレームの色,
                履歴読み: 登録.履歴読み,
                履歴書き: 登録.履歴書き,
                動きベクトル: 基本.動きベクトル,
                深度: 基本.深度,
                再構成後の色,
            };
            グラフ.パスを積む(temporal_reconstruction_pass::作る(ハンドル, 入力, 寸法));
        }
        (None, None) => {}
        _ => panic!("時間再構成の入力と画像の登録の有無が一致しない(レンダラーの配線のバグ)"),
    }
}

/// 検収が合成入力を据えた実行だけ、再構成のパスの直前へ転送を1本積む。
fn 合成入力を積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    基本: &基本画像ハンドル,
    登録: &super::super::base_images::時間再構成の登録,
    合成入力: Option<合成入力の注入入力>,
) {
    let Some(合成入力) = 合成入力 else {
        return;
    };
    let 書き戻し先 = 合成入力の書き戻し先 {
        今のフレームの色: 登録.今のフレームの色,
        履歴読み: 登録.履歴読み,
        動きベクトル: 基本.動きベクトル,
        深度: 基本.深度,
    };
    グラフ.パスを積む(合成入力の注入を作る(書き戻し先, 合成入力));
}
