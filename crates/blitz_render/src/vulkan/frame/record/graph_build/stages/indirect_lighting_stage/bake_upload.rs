//! 遠方環境と、そこから導く拡散照度・鏡面畳込みをレンダーグラフへ積む工程。受け取るのはグラフとそのフレームの
//! 描画入力とスカイビューのハンドル、返すのは無しである。焼かないフレームは1本も積まない。
//!
//! 反射率積分表と分けるのは、焼き直しの条件が違うためである。この3つは遠方環境キーが変わるたびに一緒に焼き直され、
//! 表は起動後の1回で焼き終わる。
//!
//! 宣言順を遠方環境→最詳細段の複製→拡散照度→鏡面畳込み(段ごと)に固定するのは、後段が前段の結果を読むためである。
//! レンダーグラフは宣言順に実行してバリアだけを導くため、この順序を依存解析に任せない。

use super::graph_images::{遠方環境の消費画像, 遠方環境を登録する};
use crate::vulkan::derived_environment::{copy_pass, pass as 派生パス};
use crate::vulkan::distant_environment::pass as 遠方環境パス;
use crate::vulkan::graph;
use crate::vulkan::indirect_lighting::{間接照明の描画入力, 間接照明の焼く組};

/// 遠方環境と、そこから導く拡散照度・鏡面畳込みを積む。3つは同じ条件で一緒に焼き直されるため1つの枝で扱う。
pub(super) fn 遠方環境と派生を積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    入力: &'a 間接照明の描画入力,
    スカイビュー: graph::画像ハンドル,
    消費画像: 遠方環境の消費画像,
) {
    let 間接照明の焼く組::焼く {
        遠方環境: 遠方環境入力,
        拡散照度: 拡散照度入力,
        鏡面畳込み一覧,
    } = &入力.焼く組
    else {
        return;
    };
    let 遠方環境 = 遠方環境を登録する(グラフ, &入力.遠方環境の画像);
    match &入力.焼かせる注入 {
        // 検収が与えた中身を転送で載せる。生成パスと1対1で置き換わるため、積むパスの本数は変わらない。
        Some(注入) => グラフ.パスを積む(copy_pass::書き込みパスを作る(
            遠方環境,
            入力.遠方環境の範囲,
            入力.層数,
            注入.遠方環境の元,
        )),
        None => {
            let スカイビューを読む = vec![(スカイビュー, graph::画像用途::コンピュート読み)];
            グラフ.パスを積む(遠方環境パス::作る(遠方環境, スカイビューを読む, 遠方環境入力));
        }
    }
    グラフ.パスを積む(copy_pass::最詳細段の複製を作る(
        遠方環境,
        消費画像.鏡面畳込み(),
        入力.遠方環境の範囲,
        入力.層数,
    ));
    let 遠方環境を読む = || vec![(遠方環境, graph::画像用途::コンピュート読み)];
    グラフ.パスを積む(派生パス::作る(
        派生パス::拡散照度生成のパス名,
        消費画像.拡散照度(),
        遠方環境を読む(),
        拡散照度入力,
    ));
    for 段の入力 in 鏡面畳込み一覧 {
        let 段 = 消費画像.鏡面畳込み();
        グラフ.パスを積む(派生パス::作る(派生パス::鏡面畳込み生成のパス名, 段, 遠方環境を読む(), 段の入力));
    }
}
