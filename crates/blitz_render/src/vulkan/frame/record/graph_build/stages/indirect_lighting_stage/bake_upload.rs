//! 遠方環境用スカイビューと遠方環境、そこから導く拡散照度・鏡面畳込みをレンダーグラフへ積む工程。
//! 受け取るのはグラフとそのフレームの描画入力と経路生成が読む2枚のハンドル、返すのは無しである。
//! 焼かないフレームは1本も積まない。反射率積分表と分けるのは、焼き直しの条件が違うためである
//! (この4つは遠方環境キーが変わるたびに一緒に焼き直され、表は起動後の1回で焼き終わる)。
//!
//! 宣言順を遠方環境用スカイビュー→遠方環境→最詳細段の複製→拡散照度→鏡面畳込み(段ごと)に固定するのは、
//! 後段が前段の結果を読むためである。レンダーグラフは宣言順に実行してバリアだけを導くため、
//! この順序を依存解析に任せない。

use super::super::atmosphere_lut_stage::経路生成が読む二枚;
use super::graph_images::{焼く中間画像を登録する, 遠方環境の消費画像};
use crate::distant_environment::間接照明生成パス数;
use crate::vulkan::atmosphere_lut::pass as 大気パス;
use crate::vulkan::derived_environment::{copy_pass, pass as 派生パス};
use crate::vulkan::distant_environment::pass as 遠方環境パス;
use crate::vulkan::graph;
use crate::vulkan::indirect_lighting::{遠方環境用スカイビューの焼き上げ, 間接照明の描画入力, 間接照明の焼く組};

/// 遠方環境用スカイビューと遠方環境、そこから導く拡散照度・鏡面畳込みを積む。
/// 4つは同じ条件で一緒に焼き直されるため1つの枝で扱う。
/// 本数は積んだ枝で1本ずつ加算する(理由は`indirect_lighting_stage`の冒頭)。
pub(super) fn 遠方環境と派生を積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    入力: &'a 間接照明の描画入力,
    経路の二枚: 経路生成が読む二枚,
    消費画像: 遠方環境の消費画像,
    生成パス数: &mut 間接照明生成パス数,
) {
    let 間接照明の焼く組::焼く {
        遠方環境用スカイビュー: 専用スカイビュー入力,
        遠方環境: 遠方環境入力,
        拡散照度: 拡散照度入力,
        鏡面畳込み一覧,
    } = &入力.焼く組
    else {
        return;
    };
    let 専用スカイビュー = 遠方環境用スカイビューを積む(グラフ, 専用スカイビュー入力.as_ref(), 経路の二枚, 生成パス数);
    let 遠方環境 = 焼く中間画像を登録する(グラフ, &入力.遠方環境の画像);
    match &入力.焼かせる注入 {
        // 検収が与えた中身を転送で載せる。生成パスと1対1で置き換わるため、積むパスの本数は変わらない。
        Some(注入) => グラフ.パスを積む(copy_pass::書き込みパスを作る(
            遠方環境,
            入力.遠方環境の範囲,
            入力.層数,
            注入.遠方環境の元,
        )),
        None => {
            let 専用スカイビュー = 専用スカイビュー.unwrap_or_else(|| panic!("遠方環境を生成で焼くフレームに遠方環境用スカイビューの焼き上げが無い"));
            let スカイビューを読む = vec![(専用スカイビュー, graph::画像用途::コンピュート読み)];
            グラフ.パスを積む(遠方環境パス::作る(遠方環境, スカイビューを読む, 遠方環境入力));
        }
    }
    生成パス数.遠方環境 += 1;
    グラフ.パスを積む(copy_pass::最詳細段の複製を作る(
        遠方環境,
        消費画像.鏡面畳込み(),
        入力.遠方環境の範囲,
        入力.層数,
    ));
    生成パス数.最詳細段の複製 += 1;
    let 遠方環境を読む = || vec![(遠方環境, graph::画像用途::コンピュート読み)];
    グラフ.パスを積む(派生パス::派生表現の生成パスを作る(
        派生パス::拡散照度生成のパス名,
        消費画像.拡散照度(),
        遠方環境を読む(),
        拡散照度入力,
    ));
    生成パス数.拡散照度 += 1;
    for 段の入力 in 鏡面畳込み一覧 {
        let 段 = 消費画像.鏡面畳込み();
        グラフ.パスを積む(派生パス::派生表現の生成パスを作る(
            派生パス::鏡面畳込み生成のパス名,
            段,
            遠方環境を読む(),
            段の入力,
        ));
        生成パス数.鏡面畳込み += 1;
    }
}

/// 代表天頂余弦で焼く専用スカイビューを積み、そのハンドルを返す。焼かないフレームは画像も登録しない。
/// 登録を焼くフレームだけに限るのは、誰も参照しない画像を登録してもバリアが1本も生まれないためである。
fn 遠方環境用スカイビューを積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    焼き上げ: Option<&'a 遠方環境用スカイビューの焼き上げ>,
    経路の二枚: 経路生成が読む二枚,
    生成パス数: &mut 間接照明生成パス数,
) -> Option<graph::画像ハンドル> {
    let 焼き上げ = 焼き上げ?;
    let 書き先 = 焼く中間画像を登録する(グラフ, &焼き上げ.画像);
    let 読み画像 = vec![
        (経路の二枚.透過率, graph::画像用途::コンピュート読み),
        (経路の二枚.多重散乱, graph::画像用途::コンピュート読み),
    ];
    グラフ.パスを積む(大気パス::作る(
        遠方環境パス::遠方環境用スカイビュー生成のパス名,
        書き先,
        読み画像,
        &焼き上げ.生成入力,
    ));
    生成パス数.遠方環境用スカイビュー += 1;
    Some(書き先)
}
