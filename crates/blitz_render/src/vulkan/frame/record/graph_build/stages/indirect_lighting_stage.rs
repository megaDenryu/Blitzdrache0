//! 間接照明の表現の生成をレンダーグラフの具体的なパスへ展開する。担当する工程は「そのフレームで焼く組に応じて
//! 画像を登録し、遠方環境から派生表現までを宣言順に積む」ことである。受け取るのはグラフとそのフレームの描画入力、
//! 返すのは積んだパスの本数の内訳と、標準PBRと布が参照する3枚のハンドルである。
//!
//! 宣言順を遠方環境用スカイビュー生成→遠方環境生成→最詳細段の複製→拡散照度生成→鏡面畳込み生成(段ごと)に
//! 固定するのは、後段が前段の結果を読むためである。レンダーグラフは宣言順に実行してバリアだけを導くため、
//! この順序を依存解析に任せない。
//!
//! 遠方環境用スカイビューの生成が透過率と多重散乱を、遠方環境の生成がその専用スカイビューを読み画像として
//! 宣言するのは、同じフレームで焼き直された結果を読むためである。宣言が無いとグラフはバリアを1本も置かない。
//!
//! 標準PBRと布が参照する3枚は、焼かないフレームも参照する画像として登録する。焼いた中身を次のフレームが読むため、
//! 登録しないとシーン描画がその画像への依存を宣言できない。登録と初期状態の選び方は`graph_images`が持つ。
//!
//! 本数は`グラフ.パスを積む`を呼んだ枝で1本ずつ加算する。焼き上げの計画が答える本数をそのまま転記すると、
//! 検収が読む見込みも同じ計画から導かれるため、実測と見込みが同じ導出の鏡写しになる。その形では、この工程が
//! パスを積み忘れても余分に積んでも、どちらの値も一緒に動いて検収が通ってしまう。積んだ場所で数えることで、
//! 計画が期待する本数と実際に積んだ本数の食い違いが検収に出る(参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Ic-3bの実装」)。

