//! 間接照明の表現の生成をレンダーグラフの具体的なパスへ展開する。担当する工程は「そのフレームで焼く組に応じて
//! 画像を登録し、遠方環境から派生表現までを宣言順に積む」ことである。受け取るのはグラフとそのフレームの描画入力、
//! 返すのは積んだパスの本数の内訳である。
//!
//! 宣言順を遠方環境生成→最詳細段の複製→拡散照度生成→鏡面畳込み生成(段ごと)に固定するのは、後段が前段の結果を
//! 読むためである。レンダーグラフは宣言順に実行してバリアだけを導くため、この順序を依存解析に任せない。
//!
//! 遠方環境の生成がスカイビューのベイク済み画像を読み画像として宣言するのは、同じフレームで焼き直された
//! スカイビューの結果を読むためである。宣言が無いとグラフは大気の生成との間にバリアを1本も置かない。
//!
//! 焼かない画像を1枚も登録しないのは、登録だけしてどのパスも使わない資源がバリアを1本も生まず、
//! 「参照する先がある」という誤った読み取りだけを型に残すためである。消費側(3-Ic-2)が入ると、焼かないフレームでも
//! 参照する画像として登録することになる。

use crate::distant_environment::間接照明生成パス数;
use crate::vulkan::derived_environment::{copy_pass, pass as 派生パス};
use crate::vulkan::distant_environment::pass as 遠方環境パス;
use crate::vulkan::graph;
use crate::vulkan::indirect_lighting::{登録する画像, 間接照明の描画入力, 間接照明の焼く組};

pub(in crate::vulkan::frame::record::graph_build) fn 間接照明を積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    入力: Option<&'a 間接照明の描画入力>,
    スカイビュー: Option<graph::画像ハンドル>,
) -> 間接照明生成パス数 {
    let Some(入力) = 入力 else {
        return 間接照明生成パス数::焼かない();
    };
    let スカイビュー = スカイビュー.unwrap_or_else(|| panic!("遠方環境の照明資源があるのにスカイビューのベイク済み画像が登録されていない"));
    遠方環境と派生を積む(グラフ, 入力, スカイビュー);
    反射率積分表を積む(グラフ, 入力);
    // 本数は積んだ結果を数え直さず、積む組を決めたのと同じ計画が答える。数え直すと、積む側と数える側で
    // 段の構成の導出が2つに割れる(並びの長さと計画の一致は描画入力の組み立てが不変条件として確かめている)。
    入力.計画.本数()
}

/// 遠方環境と、そこから導く拡散照度・鏡面畳込みを積む。3つは同じ条件で一緒に焼き直されるため1つの枝で扱う。
fn 遠方環境と派生を積む<'a>(
    グラフ: &mut graph::グラフ<'a>, 入力: &'a 間接照明の描画入力, スカイビュー: graph::画像ハンドル
) {
    let 間接照明の焼く組::焼く {
        遠方環境: 遠方環境入力,
        拡散照度: 拡散照度入力,
        鏡面畳込み一覧,
    } = &入力.焼く組
    else {
        return;
    };
    let 遠方環境 = 焼く画像を登録する(グラフ, &入力.遠方環境の画像);
    let 拡散照度 = 焼く画像を登録する(グラフ, &入力.拡散照度の画像);
    let 鏡面畳込み = 焼く画像を登録する(グラフ, &入力.鏡面畳込みの画像);
    let スカイビューを読む = vec![(スカイビュー, graph::画像用途::コンピュート読み)];
    グラフ.パスを積む(遠方環境パス::作る(遠方環境, スカイビューを読む, 遠方環境入力));
    グラフ.パスを積む(copy_pass::最詳細段の複製を作る(
        遠方環境,
        鏡面畳込み,
        入力.遠方環境の範囲,
        入力.層数,
    ));
    let 遠方環境を読む = || vec![(遠方環境, graph::画像用途::コンピュート読み)];
    グラフ.パスを積む(派生パス::作る(
        派生パス::拡散照度生成のパス名,
        拡散照度,
        遠方環境を読む(),
        拡散照度入力,
    ));
    for 段の入力 in 鏡面畳込み一覧 {
        グラフ.パスを積む(派生パス::作る(
            派生パス::鏡面畳込み生成のパス名,
            鏡面畳込み,
            遠方環境を読む(),
            段の入力,
        ));
    }
}

/// 反射率積分表は大気にも時刻にも依らないため、まだ1度も焼いていないフレームだけが1本積む。
fn 反射率積分表を積む<'a>(グラフ: &mut graph::グラフ<'a>, 入力: &'a 間接照明の描画入力) {
    let Some(表の入力) = &入力.反射率積分表の入力 else {
        return;
    };
    let 表 = 焼く画像を登録する(グラフ, &入力.反射率積分表の画像);
    グラフ.パスを積む(派生パス::作る(派生パス::反射率積分表生成のパス名, 表, Vec::new(), 表の入力));
}

/// このフレームで全テクセルを焼き直す画像として登録する。内容を保たないためレイアウトはUNDEFINEDから始める。
fn 焼く画像を登録する(グラフ: &mut graph::グラフ<'_>, 画像: &登録する画像) -> graph::画像ハンドル {
    グラフ.画像を登録する(
        画像.画像,
        画像.ビュー,
        graph::画像アスペクト::カラー,
        graph::焼いた画像を焼き直すときの初期状態(),
        画像.寸法,
    )
}
