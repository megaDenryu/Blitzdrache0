//! 間接照明の表現の生成をレンダーグラフの具体的なパスへ展開する。担当する工程は「そのフレームで焼く組に応じて
//! 画像を登録し、遠方環境から派生表現までを宣言順に積む」ことである。受け取るのはグラフとそのフレームの描画入力、
//! 返すのは積んだパスの本数の内訳と、標準PBRと布が参照する3枚のハンドルである。
//!
//! 宣言順を遠方環境生成→最詳細段の複製→拡散照度生成→鏡面畳込み生成(段ごと)に固定するのは、後段が前段の結果を
//! 読むためである。レンダーグラフは宣言順に実行してバリアだけを導くため、この順序を依存解析に任せない。
//!
//! 遠方環境の生成がスカイビューのベイク済み画像を読み画像として宣言するのは、同じフレームで焼き直された
//! スカイビューの結果を読むためである。宣言が無いとグラフは大気の生成との間にバリアを1本も置かない。
//!
//! 標準PBRと布が参照する3枚は、焼かないフレームも参照する画像として登録する。焼いた中身を次のフレームが読むため、
//! 登録しないとシーン描画がその画像への依存を宣言できない。登録と初期状態の選び方は`graph_images`が持つ。

use crate::distant_environment::間接照明生成パス数;
use crate::vulkan::derived_environment::{copy_pass, pass as 派生パス};
use crate::vulkan::graph;
use crate::vulkan::indirect_lighting::間接照明の描画入力;

mod bake_upload;
mod graph_images;
mod injection_upload;

use graph_images::消費する画像を登録する;
pub(in crate::vulkan::frame::record::graph_build) use graph_images::遠方環境の消費画像;

/// 積み上げの結果。本数の内訳と、消費側が読み宣言に使うハンドルである。
pub(in crate::vulkan::frame::record::graph_build) struct 間接照明の積み上げ {
    pub(in crate::vulkan::frame::record::graph_build) 生成パス数: 間接照明生成パス数,
    /// 照明問い合わせ契約が定数近似のフレームは`None`である。
    pub(in crate::vulkan::frame::record::graph_build) 消費画像: Option<遠方環境の消費画像>,
}

pub(in crate::vulkan::frame::record::graph_build) fn 間接照明を積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    入力: Option<&'a 間接照明の描画入力>,
    スカイビュー: Option<graph::画像ハンドル>,
) -> 間接照明の積み上げ {
    let Some(入力) = 入力 else {
        return 間接照明の積み上げ {
            生成パス数: 間接照明生成パス数::焼かない(),
            消費画像: None,
        };
    };
    let スカイビュー = スカイビュー.unwrap_or_else(|| panic!("遠方環境の照明資源があるのにスカイビューのベイク済み画像が登録されていない"));
    let 消費画像 = 消費する画像を登録する(グラフ, 入力);
    injection_upload::注入を積む(グラフ, 入力, 消費画像);
    bake_upload::遠方環境と派生を積む(グラフ, 入力, スカイビュー, 消費画像);
    反射率積分表を積む(グラフ, 入力, 消費画像.反射率積分表());
    // 本数は積んだ結果を数え直さず、積む組を決めたのと同じ計画が答える。数え直すと、積む側と数える側で
    // 段の構成の導出が2つに割れる(並びの長さと計画の一致は描画入力の組み立てが不変条件として確かめている)。
    間接照明の積み上げ {
        生成パス数: 入力.計画.本数(),
        消費画像: Some(消費画像),
    }
}

/// 反射率積分表は大気にも時刻にも依らないため、まだ1度も焼いていないフレームだけが1本積む。
/// 検収が遠方環境へ注入する実行は、表も転送で置き換えて期待値から標本の補間を外す。
fn 反射率積分表を積む<'a>(グラフ: &mut graph::グラフ<'a>, 入力: &'a 間接照明の描画入力, 表: graph::画像ハンドル) {
    if let Some(注入) = &入力.焼かせる注入 {
        グラフ.パスを積む(copy_pass::表の書き込みパスを作る(
            "検収の反射率積分表の注入",
            表,
            注入.反射率積分表の範囲,
            注入.反射率積分表の元,
            copy_pass::二成分テクセルのバイト数,
        ));
        return;
    }
    let Some(表の入力) = &入力.反射率積分表の入力 else {
        return;
    };
    グラフ.パスを積む(派生パス::作る(派生パス::反射率積分表生成のパス名, 表, Vec::new(), 表の入力));
}
