/// 積み上げの結果。本数の内訳と、消費側が読み宣言に使うハンドルである。
pub(in crate::vulkan::frame::record::graph_build) struct 間接照明の積み上げ {
    pub(in crate::vulkan::frame::record::graph_build) 生成パス数: 間接照明生成パス数,
    pub(in crate::vulkan::frame::record::graph_build) 消費画像: Option<遠方環境の消費画像>, // 照明問い合わせ契約が定数近似のフレームは`None`
}

pub(in crate::vulkan::frame::record::graph_build) fn 間接照明を積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    入力: Option<&'a 間接照明の描画入力>,
    経路の二枚: Option<経路生成が読む二枚>,
) -> 間接照明の積み上げ {
    let Some(入力) = 入力 else {
        return 間接照明の積み上げ {
            生成パス数: 間接照明生成パス数::焼かない(),
            消費画像: None,
        };
    };
    let 経路の二枚 = 経路の二枚.unwrap_or_else(|| panic!("遠方環境の照明資源があるのに透過率と多重散乱のベイク済み画像が登録されていない"));
    let 消費画像 = 消費する画像を登録する(グラフ, 入力);
    injection_upload::注入を積む(グラフ, 入力, 消費画像);
    let mut 生成パス数 = 間接照明生成パス数::焼かない();
    bake_upload::遠方環境と派生を積む(グラフ, 入力, 経路の二枚, 消費画像, &mut 生成パス数);
    反射率積分表を積む(グラフ, 入力, 消費画像.反射率積分表(), &mut 生成パス数);
    間接照明の積み上げ {
        生成パス数,
        消費画像: Some(消費画像),
    }
}

/// 反射率積分表は大気にも時刻にも依らないため、まだ1度も焼いていないフレームだけが1本積む。
/// 検収が遠方環境へ注入する実行は、表も転送で置き換えて期待値から標本の補間を外す。この転送は生成パスでは
/// ないため数えない(その実行の計画も反射率積分表を焼かないと答える)。
fn 反射率積分表を積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    入力: &'a 間接照明の描画入力,
    表: graph::画像ハンドル,
    生成パス数: &mut 間接照明生成パス数,
) {
    if let Some(注入) = &入力.焼かせる注入 {
        グラフ.パスを積む(copy_pass::表の書き込みパスを作る(
            "検収の反射率積分表の注入",
            表,
            注入.反射率積分表の範囲,
            注入.反射率積分表の元,
            copy_pass::二成分テクセルのバイト数,
        ));
        return;
    }
    let Some(表の入力) = &入力.反射率積分表の入力 else {
        return;
    };
    グラフ.パスを積む(派生パス::派生表現の生成パスを作る(
        派生パス::反射率積分表生成のパス名,
        表,
        Vec::new(),
        表の入力,
    ));
    生成パス数.反射率積分表 += 1;
}
