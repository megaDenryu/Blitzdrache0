//! 局所可視性補正の段階を展開する工程。受け取るのは深度のハンドルとそのフレームの入力、返す代わりに、
//! 世界が局所可視性補正を宣言したときだけ2枚の画像を登録して2本のパスをグラフへ積む。
//!
//! 積むかどうかの判断をここが持つのは、拡散間接方式がフレームの組み立て方を決める値であり、パスの宣言そのものは
//! 判断を持たないためである。積まない世界では画像の登録も1枚行わないため、レンダーグラフのバリアも1つも増えない。
//!
//! 注意: 呼び出し元はこの工程を深度プリパスとシーン描画の間へ置く。前へ置くと消去値のままの深度を読み、
//! 後ろへ置くとそのフレームのシーン描画が前フレームの可視度を読む。

use ash::vk;

use super::super::super::local_visibility_passes;
use crate::vulkan::graph;
use crate::vulkan::local_visibility::局所可視性描画入力;

/// 積んだときだけ、シーン描画が画素段で読むぼかし後の画像のハンドルを返す。読み宣言を呼び出し元が
/// シーン描画へ渡すことで、ぼかしの書き込みと画素段の読みの間にバリアが立つ。
pub(in crate::vulkan::frame::record::graph_build) fn 局所可視性を積む<'a>(
    グラフ: &mut graph::グラフ<'a>,
    深度: graph::画像ハンドル,
    入力: Option<&'a 局所可視性描画入力>,
    寸法: vk::Extent2D,
) -> Option<graph::画像ハンドル> {
    let 入力 = 入力?;
    let 生 = 登録する(グラフ, 入力.生の画像, 入力.生のビュー, 寸法);
    let ぼかし後 = 登録する(グラフ, 入力.ぼかし後の画像, 入力.ぼかし後の画像ビュー, 寸法);
    グラフ.パスを積む(local_visibility_passes::遮蔽の標本化を作る(深度, 生, 入力, 寸法));
    グラフ.パスを積む(local_visibility_passes::両側ぼかしを作る(深度, 生, ぼかし後, 入力, 寸法));
    Some(ぼかし後)
}

fn 登録する(
    グラフ: &mut graph::グラフ<'_>, 画像: vk::Image, ビュー: vk::ImageView, 寸法: vk::Extent2D
) -> graph::画像ハンドル {
    グラフ.画像を登録する(
        画像,
        ビュー,
        graph::画像アスペクト::カラー,
        graph::局所可視度の画像の前フレーム直後状態(),
        寸法,
    )
}
