//! 毎フレーム共通の外部持ち込み画像(スワップチェーン・深度・シャドウマップ・動きベクトル)と、
//! 時間再構成のパスを積むフレームだけ要る3枚(今のフレームの色・履歴の読み側と書き側)のグラフ登録。

use ash::vk;

use crate::vulkan::frame::フレーム画像一式;
use crate::vulkan::graph;
use crate::vulkan::temporal_reconstruction::時間再構成描画入力;

pub(super) struct 基本画像ハンドル {
    pub(super) スワップチェーン: graph::画像ハンドル,
    pub(super) 深度: graph::画像ハンドル,
    pub(super) シャドウマップ: graph::画像ハンドル,
    /// シーン描画と空のパスが第2のカラー添付として書く動きベクトル画像。時間再構成方式に依らず毎フレーム登録する。
    pub(super) 動きベクトル: graph::画像ハンドル,
    /// 時間再構成のパスを積むフレームだけ`Some`。積まない世界では1枚も登録せず、バリアも1つも増えない。
    pub(super) 時間再構成: Option<時間再構成の登録>,
    /// シャドウマップ資源の一辺。登録した寸法と同じ値であり、シャドウパスのビューポートがこれを読む。
    pub(super) シャドウマップ一辺: crate::cascade::影の一辺解像度,
}

/// 時間再構成のパスが読み書きする3枚のハンドル。
pub(super) struct 時間再構成の登録 {
    /// シーン・空・粒子の描画先。時間再構成のパスがこれを読む。
    pub(super) 今のフレームの色: graph::画像ハンドル,
    pub(super) 履歴読み: graph::画像ハンドル,
    pub(super) 履歴書き: graph::画像ハンドル,
}

pub(super) fn 登録する(
    グラフ: &mut graph::グラフ<'_>,
    画像一式: &フレーム画像一式,
    時間再構成入力: Option<&時間再構成描画入力>,
    寸法: vk::Extent2D,
) -> 基本画像ハンドル {
    let スワップチェーン = グラフ.画像を登録する(
        画像一式.スワップチェーン画像,
        画像一式.スワップチェーンビュー,
        graph::画像アスペクト::カラー,
        graph::取得直後の色画像状態(),
        寸法,
    );
    let 深度 = グラフ.画像を登録する(
        画像一式.深度画像,
        画像一式.深度ビュー,
        graph::画像アスペクト::深度,
        graph::前フレーム深度書き込み直後状態(),
        寸法,
    );
    let シャドウマップ寸法 = vk::Extent2D {
        width: 画像一式.シャドウマップ一辺.テクセル数(),
        height: 画像一式.シャドウマップ一辺.テクセル数(),
    };
    let シャドウマップ = グラフ.画像を登録する(
        画像一式.シャドウマップ画像,
        画像一式.シャドウマップ配列ビュー,
        graph::画像アスペクト::深度,
        graph::前フレームシャドウマップ読み直後状態(),
        シャドウマップ寸法,
    );
    let 動きベクトル = グラフ.画像を登録する(
        画像一式.動きベクトル画像,
        画像一式.動きベクトルビュー,
        graph::画像アスペクト::カラー,
        graph::前フレーム動きベクトル書き込み直後状態(),
        寸法,
    );
    基本画像ハンドル {
        スワップチェーン,
        深度,
        シャドウマップ,
        動きベクトル,
        時間再構成: 時間再構成入力.map(|入力| 時間再構成を登録する(グラフ, 入力, 寸法)),
        シャドウマップ一辺: 画像一式.シャドウマップ一辺,
    }
}

fn 時間再構成を登録する(
    グラフ: &mut graph::グラフ<'_>, 入力: &時間再構成描画入力, 寸法: vk::Extent2D
) -> 時間再構成の登録 {
    let 色 = graph::前フレーム今のフレームの色読み直後状態();
    let 履歴 = graph::履歴画像の前フレーム直後状態();
    時間再構成の登録 {
        今のフレームの色: 登録(グラフ, 入力.今のフレームの色の画像, 入力.今のフレームの色のビュー, 色, 寸法),
        履歴読み: 登録(グラフ, 入力.履歴読みの画像, 入力.履歴読みのビュー, 履歴, 寸法),
        履歴書き: 登録(グラフ, 入力.履歴書きの画像, 入力.履歴書きのビュー, 履歴, 寸法),
    }
}

fn 登録(
    グラフ: &mut graph::グラフ<'_>,
    画像: vk::Image,
    ビュー: vk::ImageView,
    初期状態: graph::画像状態,
    寸法: vk::Extent2D,
) -> graph::画像ハンドル {
    グラフ.画像を登録する(画像, ビュー, graph::画像アスペクト::カラー, 初期状態, 寸法)
}
