//! 毎フレーム共通の外部持ち込み画像(スワップチェーン・深度・多段シャドウマップ・点光源の影の立方体配列・動きベクトル)の
//! グラフ登録。時間再構成のパスを積むフレームだけ要る3枚は`temporal_reconstruction`が所有する。

mod temporal_reconstruction;

use ash::vk;

pub(super) use temporal_reconstruction::時間再構成の登録;

use crate::vulkan::frame::フレーム画像一式;
use crate::vulkan::graph;
use crate::vulkan::temporal_reconstruction::時間再構成描画入力;

pub(super) struct 基本画像ハンドル {
    pub(super) スワップチェーン: graph::画像ハンドル,
    pub(super) 深度: graph::画像ハンドル,
    pub(super) シャドウマップ: graph::画像ハンドル,
    /// 点光源の影の立方体配列。灯を1件も持たないフレームも登録するのは、画素段が常にこの資源を束縛しており、
    /// 登録しないとレイアウトの追跡がその1枚だけ抜けるためである。
    pub(super) 点光源の影: graph::画像ハンドル,
    /// シーン描画と空のパスが第2のカラー添付として書く動きベクトル画像。時間再構成方式に依らず毎フレーム登録する。
    pub(super) 動きベクトル: graph::画像ハンドル,
    /// 時間再構成のパスを積むフレームだけ`Some`。積まない世界では1枚も登録せず、バリアも1つも増えない。
    pub(super) 時間再構成: Option<時間再構成の登録>,
    /// シャドウマップ資源の一辺。登録した寸法と同じ値であり、シャドウパスのビューポートがこれを読む。
    pub(super) シャドウマップ一辺: crate::cascade::影の一辺解像度,
}

pub(super) fn 登録する(
    グラフ: &mut graph::グラフ<'_>,
    画像一式: &フレーム画像一式<'_>,
    時間再構成入力: Option<&時間再構成描画入力>,
    寸法: vk::Extent2D,
) -> 基本画像ハンドル {
    let スワップチェーン = グラフ.画像を登録する(
        画像一式.スワップチェーン画像,
        画像一式.スワップチェーンビュー,
        graph::画像アスペクト::カラー,
        graph::取得直後の色画像状態(),
        寸法,
    );
    let 深度 = グラフ.画像を登録する(
        画像一式.深度画像,
        画像一式.深度ビュー,
        graph::画像アスペクト::深度,
        graph::前フレーム深度書き込み直後状態(),
        寸法,
    );
    let シャドウマップ寸法 = vk::Extent2D {
        width: 画像一式.シャドウマップ一辺.テクセル数(),
        height: 画像一式.シャドウマップ一辺.テクセル数(),
    };
    let シャドウマップ = グラフ.画像を登録する(
        画像一式.シャドウマップ画像,
        画像一式.シャドウマップ配列ビュー,
        graph::画像アスペクト::深度,
        graph::前フレームシャドウマップ読み直後状態(),
        シャドウマップ寸法,
    );
    let 点光源の影の寸法 = vk::Extent2D {
        width: crate::point_light_shadow::点光源の影の面の一辺,
        height: crate::point_light_shadow::点光源の影の面の一辺,
    };
    let 点光源の影 = グラフ.画像を登録する(
        画像一式.点光源の影の画像,
        画像一式.点光源の影の立方体配列ビュー,
        graph::画像アスペクト::深度,
        graph::前フレームシャドウマップ読み直後状態(),
        点光源の影の寸法,
    );
    let 動きベクトル = グラフ.画像を登録する(
        画像一式.動きベクトル画像,
        画像一式.動きベクトルビュー,
        graph::画像アスペクト::カラー,
        graph::前フレーム動きベクトル書き込み直後状態(),
        寸法,
    );
    基本画像ハンドル {
        スワップチェーン,
        深度,
        シャドウマップ,
        点光源の影,
        動きベクトル,
        時間再構成: 時間再構成入力.map(|入力| temporal_reconstruction::登録する(グラフ, 入力, 寸法)),
        シャドウマップ一辺: 画像一式.シャドウマップ一辺,
    }
}
