//! 読み戻しコピーパスの宣言。読み戻し要求時のみグラフへ積む(判断9のスモーク用途)。
//! カラー画像を転送元として読み、ホスト可視バッファへコピーする。

use ash::vk;

use crate::vulkan::frame::copy;
use crate::vulkan::graph::{パス宣言, パス種別, 画像ハンドル, 画像用途};

pub(super) fn 作る<'a>(カラー: 画像ハンドル, バッファ: vk::Buffer, 寸法: vk::Extent2D) -> パス宣言<'a> {
    パス宣言::生成する(
        "読み戻しコピー",
        vec![(カラー, 画像用途::転送元)],
        Vec::new(),
        Vec::new(),
        Vec::new(),
        パス種別::転送,
        move |文脈| {
            let 画像 = 文脈.画像を解決する(カラー);
            copy::コピーを記録する(文脈.device(), 文脈.コマンドバッファ(), 画像, バッファ, 寸法);
        },
    )
}
