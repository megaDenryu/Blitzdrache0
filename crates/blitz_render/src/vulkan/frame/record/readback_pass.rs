//! 読み戻しコピーパスの宣言。読み戻し要求時のみグラフへ積む(判断9のスモーク用途)。
//! 転送元の画像を読み、ホスト可視バッファへコピーする。写す面は読み戻し対象が答える(色の画像は色の面、深度画像は深度の面)。

use ash::vk;

use crate::vulkan::frame::copy;
use crate::vulkan::graph::{パス宣言, パス種別, 画像ハンドル, 画像用途};
use crate::vulkan::readback::読み戻し対象;

pub(super) fn 作る<'a>(
    転送元: 画像ハンドル, バッファ: vk::Buffer, 対象: 読み戻し対象, 寸法: vk::Extent2D
) -> パス宣言<'a> {
    パス宣言::生成する(
        "読み戻しコピー",
        vec![(転送元, 画像用途::転送元)],
        Vec::new(),
        Vec::new(),
        Vec::new(),
        パス種別::転送,
        move |文脈| {
            let 画像 = 文脈.画像を解決する(転送元);
            copy::コピーを記録する(文脈.device(), 文脈.コマンドバッファ(), 画像, バッファ, 寸法, 対象.画像の面());
        },
    )
}
