//! 深度プリパスの宣言。深度アタッチメントだけを持ち、色を1つも書かない。
//!
//! 深度を消去するのはこのパスである。プリパスを積むフレームでは、シーン描画より先にこのパスが深度を消去して書き切るため、
//! シーン描画の側は深度を消去せず既存の内容を読み込む(参照: `graph_build::stages`の`シーンを積む`)。
//! 両方が消去すると、シーン描画の消去でプリパスの結果が丸ごと捨てられ、等値の比較で1画素も描かれなくなる。
//!
//! 布を描かないのは、深度プリパスの対象が不透明な材質描画族だけだからである。布は色パスでより近いものを描いて深度も書くため、
//! プリパスの有無で結果が変わらない(参照: `_doc/設計/放射輝度問い合わせ階層.md`「IIaの実装設計」)。

use ash::vk;

use super::pass_names;
use crate::clear_color::クリアカラー;
use crate::vulkan::frame::{depth_prepass_draw, ジオメトリ入力, 共有セット束縛};
use crate::vulkan::graph::{
    カラー添付列, クリア指定, バッファハンドル, バッファ用途, パス宣言, パス種別, 深度アタッチメント, 画像ハンドル, 画像用途,
};

pub(super) fn 深度プリパスを宣言する<'a>(
    深度: 画像ハンドル,
    スキン済み頂点: Option<バッファハンドル>,
    ジオメトリ一覧: &'a [ジオメトリ入力],
    共有: 共有セット束縛<'a>,
    寸法: vk::Extent2D,
) -> パス宣言<'a> {
    // 注意: クリア指定のカラー値はカラーアタッチメントを持たないため使われない(深度のみのパス)。
    // 0.0は常に正規化範囲内のため、この生成呼び出しが失敗することはない。
    let ダミークリア色 =
        クリアカラー::生成する(0.0, 0.0, 0.0, 0.0).unwrap_or_else(|誤り| panic!("深度プリパスのダミークリア色生成が失敗した(実装のバグ): {誤り}"));
    // スキン付きシーンでは頂点バッファがスキニングパスの出力のため、依存を読み宣言で表す(判断44)。
    let 読みバッファ一覧 = スキン済み頂点.map_or(Vec::new(), |ハンドル| vec![(ハンドル, バッファ用途::頂点読み)]);

    パス宣言::生成する(
        pass_names::深度プリパス,
        Vec::new(),
        vec![(深度, 画像用途::深度出力)],
        読みバッファ一覧,
        Vec::new(),
        パス種別::グラフィックス {
            カラー: カラー添付列::無し,
            深度: Some(深度アタッチメント::全体(深度)),
            クリア指定: クリア指定::クリアする {
                カラー: ダミークリア色
            },
        },
        move |文脈| {
            depth_prepass_draw::描画コマンドを積む(文脈.device(), 文脈.コマンドバッファ(), 寸法, ジオメトリ一覧, 共有);
        },
    )
}
