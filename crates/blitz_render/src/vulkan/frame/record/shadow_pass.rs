//! 距離区分1つぶんのシャドウパスの宣言(判断35・OW5第5段): 深度のみのグラフィックスパス。
//! 頂点シェーダーが位置をその距離区分のライトビュー射影で変換し、画素段は空(色を書かない)。
//! シーン描画と同じ頂点/インデックスバッファ・ジオメトリのセットを、シャドウ専用パイプラインで束ね直して描画する。
//!
//! 描くのはその距離区分のライト視錐台が通した候補だけである(第6段の距離区分別の可視個体の選別)。
//! 描く先は配列画像のその距離区分の層だけであり、グラフの追跡は配列全体を1資源として行う。

use ash::vk;

use super::scene_pass::布ドロー;
use super::shadow_draw;
use crate::cascade::{影の一辺解像度, 距離区分番号};
use crate::vulkan::frame::{シャドウ描画入力, 共有セット束縛};
use crate::vulkan::graph::{
    カラー添付列, クリア指定, バッファハンドル, バッファ用途, パス宣言, パス種別, 深度アタッチメント, 画像ハンドル, 画像用途,
};

/// 1つの距離区分を描く先。配列画像そのもの・その距離区分の層ビュー・一辺の3つは常に同じ資源から来る組であり、
/// 別々の引数として並べると層ビューだけ別の距離区分のものを渡す誤りを型が止められない。
#[derive(Clone, Copy)]
pub(super) struct シャドウの描き先 {
    pub(super) 画像: 画像ハンドル,
    pub(super) 層ビュー: vk::ImageView,
    pub(super) 一辺: 影の一辺解像度,
}

pub(super) fn 作る<'a>(
    番号: 距離区分番号,
    描き先: シャドウの描き先,
    スキン済み頂点: Option<バッファハンドル>,
    布ドロー: Option<布ドロー<'a>>,
    入力一覧: &'a [シャドウ描画入力],
    共有: 共有セット束縛<'a>,
) -> パス宣言<'a> {
    // 注意: クリア指定のカラー値はカラーアタッチメントを持たないため使われない
    // (深度のみのパス。rendering_setupはカラーハンドルがNoneならこの値を読まない)。
    // 0.0は常に正規化範囲内のため、このgenerate呼び出しが失敗することはない。
    let ダミークリア色 = crate::clear_color::クリアカラー::生成する(0.0, 0.0, 0.0, 0.0)
        .unwrap_or_else(|誤り| panic!("シャドウパスのダミークリア色生成が失敗した(実装のバグ): {誤り}"));
    // スキン付きシーンでは頂点バッファがスキニングパスの出力のため、依存を読み宣言で表す(判断44)。
    // 布があれば布頂点への依存も同様に宣言する(判断54: 布もシャドウを落とす)。
    let mut 読みバッファ一覧 = スキン済み頂点.map_or(Vec::new(), |ハンドル| vec![(ハンドル, バッファ用途::頂点読み)]);
    if let Some(布) = &布ドロー {
        読みバッファ一覧.push((布.頂点ハンドル, バッファ用途::頂点読み));
    }

    パス宣言::生成する(
        番号.シャドウパス名(),
        Vec::new(),
        vec![(描き先.画像, 画像用途::深度出力)],
        読みバッファ一覧,
        Vec::new(),
        パス種別::グラフィックス {
            カラー: カラー添付列::無し,
            深度: Some(深度アタッチメント::層(描き先.画像, 描き先.層ビュー)),
            クリア指定: クリア指定::クリアする {
                カラー: ダミークリア色
            },
        },
        move |文脈| shadow_draw::記録する(文脈.device(), 文脈.コマンドバッファ(), 番号, 描き先.一辺, 入力一覧, 布ドロー, 共有),
    )
}
