//! 影を落とす灯1件の1つの面ぶんの記録パスの宣言(判断n): 深度のみのグラフィックスパスである。
//! 頂点シェーダーが位置をその面のライトビュー射影で写し、画素段は空(色を書かない)である。
//!
//! 描く先は立方体配列のその層だけであり、グラフの追跡は配列全体を1資源として行う。積むのは影を落とす灯の
//! 件数×6本であり、灯を1件も持たない世界では1本も積まれない。
//!
//! パス名を面ごとに変えないのは、24本のGPU時間を1つの区間として集計するためである。同じ名前がフレーム内に
//! 何度も現れたときに足して1標本にする仕組みを計測が既に持ち、これが「フレームの中で先に足した1標本を窓へ入れる」
//! そのものである(参照: `crates/blitz_render/src/vulkan/gpu_timing/readback.rs`)。

use ash::vk;

use super::point_light_shadow_draw;
use crate::cube_image::立方体の面;
use crate::vulkan::frame::{共有セット束縛, 点光源の影の描画発行, 点光源の影の束縛};
use crate::vulkan::graph::{
    カラー添付列, クリア指定, パス宣言, パス種別, 深度アタッチメント, 画像ハンドル, 画像用途
};
use crate::vulkan::point_light_shadow_plan::影を落とす灯;

/// この記録パス1本の名前。合計の集計はこの名前の重なりが担う。
pub(crate) const 点光源の影: &str = "点光源の影";

/// 1つの面を描く先。配列画像そのものとその面の層ビューは常に同じ資源から来る組であり、別々の引数として
/// 並べると層ビューだけ別の面のものを渡す誤りを型が止められない。
#[derive(Clone, Copy)]
pub(super) struct 点光源の影の描き先 {
    pub(super) 画像: 画像ハンドル,
    pub(super) 層ビュー: vk::ImageView,
}

pub(super) fn 作る<'a>(
    灯: 影を落とす灯,
    面: 立方体の面,
    描き先: 点光源の影の描き先,
    束縛: 点光源の影の束縛,
    発行一覧: &'a [点光源の影の描画発行],
    共有: 共有セット束縛<'a>,
) -> パス宣言<'a> {
    // 注意: クリア指定のカラー値はカラーアタッチメントを持たないため使われない(深度のみのパス)。
    let ダミークリア色 = crate::clear_color::クリアカラー::生成する(0.0, 0.0, 0.0, 0.0)
        .unwrap_or_else(|誤り| panic!("点光源の影のパスのダミークリア色生成が失敗した(実装のバグ): {誤り}"));
    パス宣言::生成する(
        点光源の影,
        Vec::new(),
        vec![(描き先.画像, 画像用途::深度出力)],
        Vec::new(),
        Vec::new(),
        パス種別::グラフィックス {
            カラー: カラー添付列::無し,
            深度: Some(深度アタッチメント::層(描き先.画像, 描き先.層ビュー)),
            クリア指定: クリア指定::クリアする {
                カラー: ダミークリア色
            },
        },
        move |文脈| {
            point_light_shadow_draw::記録する(文脈.device(), 文脈.コマンドバッファ(), 灯, 面, 束縛, 発行一覧, 共有);
        },
    )
}
