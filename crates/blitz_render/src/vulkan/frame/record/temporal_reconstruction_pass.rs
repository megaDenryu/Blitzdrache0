//! 時間再構成パスの宣言。今のフレームの色・履歴の読み側・動きベクトル・深度を画素段で読み、全画面三角形で
//! HDR中間画像と履歴の書き側へ再構成後の色を書く。
//! 記録クロージャの中身は`fullscreen_draw`が担う(begin/end renderingは実行器が担う)。
//!
//! 注意: 履歴の読み側と書き側は同じフレームで別の画像でなければならない。同じ画像を渡すと、このパスが
//! 標本で読みながらカラー添付として書くことになり、Vulkanが結果を定めない。読み書きの分離は
//! `vulkan/temporal_reconstruction/history_state.rs`が保つ。

use ash::vk;

use super::fullscreen_draw;
use crate::vulkan::graph::{カラー添付列, パス宣言, パス種別, 画像ハンドル, 画像用途};
use crate::vulkan::temporal_reconstruction::時間再構成描画入力;

/// このパスが読み書きする4つのハンドル。5つを位置引数で並べると対応を目で追う必要が出るため、名前付きで渡す。
#[derive(Clone, Copy)]
pub(super) struct 時間再構成のハンドル組 {
    pub(super) 今のフレームの色: 画像ハンドル,
    pub(super) 履歴読み: 画像ハンドル,
    pub(super) 履歴書き: 画像ハンドル,
    pub(super) 動きベクトル: 画像ハンドル,
    pub(super) 深度: 画像ハンドル,
    pub(super) 再構成後の色: 画像ハンドル,
}

pub(super) fn 作る<'a>(
    ハンドル: 時間再構成のハンドル組, 入力: &'a 時間再構成描画入力, 寸法: vk::Extent2D
) -> パス宣言<'a> {
    パス宣言::生成する(
        "時間再構成",
        vec![
            (ハンドル.今のフレームの色, 画像用途::シェーダー読み画素段),
            (ハンドル.履歴読み, 画像用途::履歴の画素段参照),
            (ハンドル.動きベクトル, 画像用途::シェーダー読み画素段),
            (ハンドル.深度, 画像用途::深度シェーダー読み),
        ],
        vec![
            (ハンドル.再構成後の色, 画像用途::カラー出力),
            (ハンドル.履歴書き, 画像用途::履歴のカラー出力),
        ],
        Vec::new(),
        Vec::new(),
        パス種別::グラフィックス {
            カラー: カラー添付列::色と履歴 {
                色: ハンドル.再構成後の色,
                履歴: ハンドル.履歴書き,
            },
            深度: None,
            クリア指定: fullscreen_draw::黒クリア(),
        },
        move |文脈| {
            fullscreen_draw::コマンドを積む(
                文脈.device(),
                文脈.コマンドバッファ(),
                入力.pipeline,
                入力.layout,
                入力.セット,
                寸法,
                Some(&入力.即時定数),
            );
        },
    )
}
