//! そのフレームの点光源の影の記録が、面ごとの絞りで何件を判定し何件を通し、何回描いたかの計器。
//! 担当するのは、絞った地点で数えることだけである。
//!
//! 絞る前と後の両方を数えるのは、片方だけでは絞りが効いているかを値から読めないためである。通した件数だけでは、
//! それが「全部通った」のか「大半を落として残った」のかが分からない。
//!
//! 注意: 内側の可変性で数えるのは、コマンド記録の閉包が共有参照しか捕らえられないためである。
//! 1フレームの記録は1つのスレッドが順に行うため`Cell`で足りる。

use std::cell::Cell;

use crate::renderer::点光源の影の記録内訳;

#[derive(Default)]
pub(crate) struct 点光源の影の記録計数 {
    記録した面の数: Cell<u64>,
    判定した発行数: Cell<u64>,
    候補になった発行数: Cell<u64>,
    描画数: Cell<u64>,
}

impl 点光源の影の記録計数 {
    /// 前提: 1フレームにつき記録を始める前に1回だけ呼ぶ。呼ばないと前のフレームの回数へ積み上がる。
    pub(crate) fn 数え直す(&self) {
        self.記録した面の数.set(0);
        self.判定した発行数.set(0);
        self.候補になった発行数.set(0);
        self.描画数.set(0);
    }

    /// その面で絞りに掛けた発行の数。面ごとに1回呼ぶため、呼ばれた回数がそのまま記録した面の数になる。
    pub(crate) fn 面の判定した発行を数える(&self, 件数: usize) {
        self.記録した面の数.set(self.記録した面の数.get().saturating_add(1));
        self.判定した発行数.set(self.判定した発行数.get().saturating_add(件数を数値にする(件数)));
    }

    pub(crate) fn 候補を数える(&self) {
        self.候補になった発行数.set(self.候補になった発行数.get().saturating_add(1));
    }

    pub(crate) fn 描画を数える(&self) {
        self.描画数.set(self.描画数.get().saturating_add(1));
    }

    /// そのフレームの内訳。
    pub(crate) fn 内訳を作る(&self) -> 点光源の影の記録内訳 {
        点光源の影の記録内訳::生成する(
            self.記録した面の数.get(),
            self.判定した発行数.get(),
            self.候補になった発行数.get(),
            self.描画数.get(),
        )
    }
}

fn 件数を数値にする(件数: usize) -> u64 {
    u64::try_from(件数).unwrap_or_else(|_| panic!("点光源の影の判定件数がu64に収まらない: {件数}"))
}
