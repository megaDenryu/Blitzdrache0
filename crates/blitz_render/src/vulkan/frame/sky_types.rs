//! 空パス1フレームぶんの入力。フレーム構成に空段階があるときのみ`Some`で渡す。

use ash::vk;

/// 空パスが束縛する資源。夜空放射輝度や太陽円盤の値は空パス定数(binding9)に載るため、ここには載らない。
///
/// `ディスクリプタセット`は走査順で最初の描画対象のものである。空のシェーダーがそこから読むのは空パス定数とビュー定数だけであり、
/// どの描画対象のセットでも同じ資源を指すため、可視判定の結果でこの値は変わらない(布の描画と同じ理由)。
/// `標本セット`はset1で、スカイビューのベイク済み画像と透過率のベイク済み画像と媒体のシェーダー定数を結ぶ。
pub(crate) struct 空描画入力 {
    pub(crate) pipeline: vk::Pipeline,
    pub(crate) layout: vk::PipelineLayout,
    pub(crate) ディスクリプタセット: vk::DescriptorSet,
    pub(crate) 標本セット: vk::DescriptorSet,
}

/// 空中遠近合成パス1フレームぶんの入力。大気のベイク済み画像方式で合成を切っていないフレームだけ`Some`で渡す。
///
/// 最遠距離をここが運ぶのは、ボリュームを焼いた条件と参照する条件を同じ値から作るためである。空パス定数へ
/// 写すと、焼いた刻みと参照する刻みが別の経路で更新されて食い違いうる。
///
/// `シーンセット`はset0で、空パス定数とビュー定数を読むために走査順で最初の描画対象のセットを借りる
/// (空パスと同じ理由)。`合成セット`はset1で、深度と空中遠近ボリュームを結ぶ。`最遠距離`はボリュームの
/// 奥行きの目盛りの最遠端(メートル)。
pub(crate) struct 空中遠近合成描画入力 {
    pub(crate) pipeline: vk::Pipeline,
    pub(crate) layout: vk::PipelineLayout,
    pub(crate) シーンセット: vk::DescriptorSet,
    pub(crate) 合成セット: vk::DescriptorSet,
    pub(crate) 最遠距離: f32,
}
