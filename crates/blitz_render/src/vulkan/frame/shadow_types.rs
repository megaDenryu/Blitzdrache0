//! シャドウパスが1フレームに受け取る入力の型。距離区分ごとに描く個体が違うため、1発行ぶんの入力と、それを距離区分の数だけ並べた器の2つを持つ。
//! 距離区分の器を型にするのは、距離区分番号でしか引けないようにして、影段階の展開だけが距離区分の走査順を持つという規律を型で示すためである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」

use ash::vk;

use crate::cascade::{距離区分数, 距離区分番号};
use crate::vulkan::relative_anchor::カメラ相対の基準原点;

/// シャドウパス(判断35)の距離区分1つぶんの1発行の入力。シーンパスと同じ
/// 頂点/インデックスバッファ・ジオメトリのセットを、シャドウ専用の
/// パイプライン/layoutで束ね直すだけのため`ジオメトリ入力`とは別型にする。
/// 材質のセットも照明問い合わせのセットも読まないため持たない。
pub(crate) struct シャドウ描画入力 {
    pub(crate) pipeline: vk::Pipeline,
    pub(crate) layout: vk::PipelineLayout,
    pub(crate) 頂点バッファ: vk::Buffer,
    pub(crate) インデックスバッファ: vk::Buffer,
    pub(crate) 先頭インデックス: u32, // この発行が描き始めるインデックスの位置。プリミティブごとに発行を分けるため、メッシュ全体の先頭とは限らない。
    pub(crate) インデックス数: u32,
    pub(crate) 頂点基準: i32,         // インデックスの値へ足す頂点番号。プリミティブが自分の頂点範囲を持つ形式のために運ぶ。
    pub(crate) インスタンス数: u32,   // その距離区分のライト視錐台が通した個体の数であり、距離区分ごとに違う値になる。
    pub(crate) 先頭インスタンス: u32, // 可視ID列のうちこの発行が読み始める位置。その距離区分の区間の中のこの段の開始である。
    pub(crate) ジオメトリセット: vk::DescriptorSet,
    pub(crate) 相対の基準原点: カメラ相対の基準原点,
}

/// 距離区分ごとのシャドウ描画入力の並び。距離区分別の可視個体の選別では距離区分ごとに描く個体が違うため、距離区分の数だけ別々の列を持つ。
/// 添字でなく`距離区分番号`で引かせるのは、影段階の展開が距離区分の走査順を持つ唯一の場所であることを型で示すためである。
#[derive(Clone, Copy)]
pub(crate) struct 距離区分別のシャドウ入力<'a> {
    距離区分ごと: &'a [Vec<シャドウ描画入力>; 距離区分数],
}

impl<'a> 距離区分別のシャドウ入力<'a> {
    pub(crate) fn 生成する(距離区分ごと: &'a [Vec<シャドウ描画入力>; 距離区分数]) -> Self {
        Self { 距離区分ごと }
    }

    pub(crate) fn 距離区分(self, 番号: 距離区分番号) -> &'a [シャドウ描画入力] {
        &self.距離区分ごと[番号.添字()]
    }
}
