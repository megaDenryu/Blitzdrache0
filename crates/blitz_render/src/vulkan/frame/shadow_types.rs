//! シャドウパスが1フレームに受け取る入力の型。帯ごとに描く個体が違うため、1発行ぶんの入力と、それを帯の数だけ並べた器の2つを持つ。
//! 帯の器を型にするのは、帯番号でしか引けないようにして、影段階の展開だけが帯の走査順を持つという規律を型で示すためである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の帯別区間(4区分並べの後継)」

use ash::vk;

use crate::cascade::{帯数, 帯番号};
use crate::vulkan::relative_anchor::カメラ相対アンカー;

/// シャドウパス(判断35)の帯1つぶんの1発行の入力。シーンパスと同じ
/// 頂点/インデックスバッファ・ディスクリプタセットを、シャドウ専用の
/// パイプライン/layoutで束ね直すだけのため`ジオメトリ入力`とは別型にする。
pub(crate) struct シャドウ描画入力 {
    pub(crate) pipeline: vk::Pipeline,
    pub(crate) layout: vk::PipelineLayout,
    pub(crate) 頂点バッファ: vk::Buffer,
    pub(crate) インデックスバッファ: vk::Buffer,
    pub(crate) インデックス数: u32,
    /// この描画発行で描く個体の数。その帯のライト視錐台が通した個体の数であり、帯ごとに違う値になる。
    pub(crate) インスタンス数: u32,
    /// 可視ID列のうちこの発行が読み始める位置。その帯の区間の中のこの段の開始である。
    pub(crate) 先頭インスタンス: u32,
    pub(crate) ディスクリプタセット: vk::DescriptorSet,
    pub(crate) 相対アンカー: カメラ相対アンカー,
}

/// 帯ごとのシャドウ描画入力の並び。帯別カリングでは帯ごとに描く個体が違うため、帯の数だけ別々の列を持つ。
/// 添字でなく`帯番号`で引かせるのは、影段階の展開が帯の走査順を持つ唯一の場所であることを型で示すためである。
#[derive(Clone, Copy)]
pub(crate) struct 帯別シャドウ入力<'a> {
    帯ごと: &'a [Vec<シャドウ描画入力>; 帯数],
}

impl<'a> 帯別シャドウ入力<'a> {
    pub(crate) fn 生成する(帯ごと: &'a [Vec<シャドウ描画入力>; 帯数]) -> Self {
        Self { 帯ごと }
    }

    pub(crate) fn 帯(self, 番号: 帯番号) -> &'a [シャドウ描画入力] {
        &self.帯ごと[番号.添字()]
    }
}
