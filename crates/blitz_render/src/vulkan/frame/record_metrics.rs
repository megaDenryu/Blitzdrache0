//! そのフレームのコマンド記録が数える計器の束。担当するのは、記録の局面が受け取る計器を1つの値にまとめ、
//! フレームの先頭で数え直す地点を1つにすることである。
//!
//! 別々に持ち回らないのは、どれもコマンドを積む地点でしか正しく数えられず、一部だけを数え直す間違いを
//! 起こしうるためである。束縛の回数は`bind_tally`、描画と切替の回数は`draw_switch_tally`が数える。

use super::bind_tally::セット別束縛計数;
use super::draw_switch_tally::記録側切替計数;
use super::point_light_shadow_tally::点光源の影の記録計数;

#[derive(Default)]
pub(crate) struct 記録の計器 {
    セット別束縛: セット別束縛計数,
    描画切替: 記録側切替計数,
    点光源の影: 点光源の影の記録計数,
}

impl 記録の計器 {
    /// 前提: 1フレームにつき記録を始める前に1回だけ呼ぶ。
    pub(crate) fn 数え直す(&self) {
        self.セット別束縛.数え直す();
        self.描画切替.数え直す();
        self.点光源の影.数え直す();
    }

    pub(crate) const fn セット別束縛(&self) -> &セット別束縛計数 {
        &self.セット別束縛
    }

    pub(crate) const fn 描画切替(&self) -> &記録側切替計数 {
        &self.描画切替
    }

    /// 面ごとの絞りと発行の回数。可視ID列を読むパスの計数と別に持つのは、点光源の影が可視ID列を通らないためである。
    pub(crate) const fn 点光源の影(&self) -> &点光源の影の記録計数 {
        &self.点光源の影
    }
}
