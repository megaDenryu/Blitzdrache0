use super::未送信のコマンドバッファ数;

#[test]
fn 積み始めと送信完了が釣り合えば1本も残らない() {
    let 勘定 = 未送信のコマンドバッファ数::零から数え始める();
    勘定.積み始めた1本を加える();
    勘定.積み始めた1本を加える();
    勘定.送信し終えた1本を差し引く();
    勘定.送信し終えた1本を差し引く();
    assert_eq!(勘定.今の本数(), 0);
    勘定.未送信が1本も残っていないことを確かめる();
}

#[test]
#[should_panic(expected = "送信されないまま残っている")]
fn 閉じずに捨てた1本を破棄時の確認が止める() {
    let 勘定 = 未送信のコマンドバッファ数::零から数え始める();
    勘定.積み始めた1本を加える();
    勘定.未送信が1本も残っていないことを確かめる();
}

#[test]
#[should_panic(expected = "送信完了を数えた")]
fn 積み始めていない送信完了を止める() {
    let 勘定 = 未送信のコマンドバッファ数::零から数え始める();
    勘定.送信し終えた1本を差し引く();
}
