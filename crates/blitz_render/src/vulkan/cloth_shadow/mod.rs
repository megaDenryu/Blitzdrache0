//! 布専用シャドウ経路の資源: 布だけを描くシャドウパイプラインと、そのパイプラインが束縛するディスクリプタ。
//! 布付き起動のときだけ`描画段階資源`が保持し、シャドウパスの布の記録だけがこの一式を束縛する。
//!
//! 通常の描画対象と同じシャドウパイプラインで布を描くと、布の頂点へ走査順で最初の描画対象の個体変換が掛かり、
//! 布の影がどの描画対象が先に来るかで動く。この一式はその依存を断つためにあり、シェーダーもディスクリプタも
//! 描画対象から1つも借りない(参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「描画段階資源の器と布専用シャドウ経路」)。
//! 固定機能の状態は通常のシャドウパイプラインと同一のため、`シャドウパイプライン`をそのまま使う。

mod descriptor;

use crate::error::レンダラーエラー;
use crate::shader_set::シェーダー一式;
use crate::vulkan::frame::布シャドウ描画入力;
use crate::vulkan::pipeline::シャドウパイプライン;
use crate::vulkan::sync::フレームスロット添字;
use crate::vulkan::uniform::フレームシェーダー定数一式;

pub(crate) struct 布シャドウ資源 {
    ディスクリプタ: descriptor::布シャドウディスクリプタ,
    パイプライン: シャドウパイプライン,
}

impl 布シャドウ資源 {
    pub(crate) fn 生成する(
        device: &ash::Device,
        シェーダー定数: &フレームシェーダー定数一式,
        シェーダー: &シェーダー一式,
    ) -> Result<Self, レンダラーエラー> {
        let ディスクリプタ = descriptor::生成する(device, シェーダー定数)?;
        let パイプライン = match シャドウパイプライン::生成する(device, ディスクリプタ.layout(), シェーダー) {
            Ok(パイプライン) => パイプライン,
            Err(誤り) => {
                ディスクリプタ.破棄する(device);
                return Err(誤り);
            }
        };
        Ok(Self {
            ディスクリプタ,
            パイプライン,
        })
    }

    pub(crate) fn 描画入力を作る(&self, フレーム添字: フレームスロット添字) -> 布シャドウ描画入力 {
        布シャドウ描画入力 {
            pipeline: self.パイプライン.handle,
            layout: self.パイプライン.layout,
            ディスクリプタセット: self.ディスクリプタ.set(フレーム添字),
        }
    }

    /// 注意: パイプラインをディスクリプタより先に破棄する(パイプラインレイアウトがディスクリプタセットレイアウトを参照するため)。
    /// 前提: レンダラー全体の破棄順は renderer/destroy.rs が持ち、この一式は`描画段階資源`の1段として呼ばれる(GPU待機済み)。
    pub(crate) fn 破棄する(&self, device: &ash::Device) {
        self.パイプライン.破棄する(device);
        self.ディスクリプタ.破棄する(device);
    }
}
