//! 布専用シャドウ経路の資源: 布だけを描くシャドウパイプライン。
//! 布付き起動のときだけ`描画段階資源`が保持し、シャドウパスの布の記録だけがこのパイプラインを束縛する。
//!
//! 通常の描画対象と同じシャドウパイプラインで布を描くと、布の頂点へ走査順で最初の描画対象の個体変換が掛かり、
//! 布の影がどの描画対象が先に来るかで動く。この資源はその依存を断つためにあり、シェーダーもセットも
//! 描画対象から1つも借りない(参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「描画段階資源の器と布専用シャドウ経路」)。
//! 固定機能の状態は通常のシャドウパイプラインと同一のため、`シャドウパイプライン`をそのまま使う。
//!
//! 束縛するのはビューとパスのセット(set0)1つだけである。多段影定数はそのセットが持ち、描画対象の登録有無と無関係に
//! 存在するため、布のためだけの専用ディスクリプタは要らない。

use ash::vk;

use crate::error::レンダラーエラー;
use crate::shader_set::シェーダー一式;
use crate::vulkan::allocator::GPU資源の確保係;
use crate::vulkan::frame::布シャドウ描画入力;
use crate::vulkan::pipeline::シャドウパイプライン;

pub(crate) struct 布シャドウ資源 {
    パイプライン: シャドウパイプライン,
}

impl 布シャドウ資源 {
    /// `ビューとパスlayout`はscene系と同じset0のレイアウトである。ジオメトリのセットは読まないため宣言しない。
    pub(crate) fn 生成する(
        確保係: &GPU資源の確保係<'_>,
        ビューとパスlayout: vk::DescriptorSetLayout,
        シェーダー: &シェーダー一式,
    ) -> Result<Self, レンダラーエラー> {
        let パイプライン = シャドウパイプライン::生成する(確保係, &[ビューとパスlayout], シェーダー)?;
        Ok(Self { パイプライン })
    }

    pub(crate) fn 描画入力を作る(&self) -> 布シャドウ描画入力 {
        布シャドウ描画入力 {
            pipeline: self.パイプライン.handle,
            layout: self.パイプライン.パイプラインレイアウトのハンドル(),
        }
    }

    /// 前提: レンダラー全体の破棄順は renderer/destroy.rs が持ち、この一式は`描画段階資源`の1段として呼ばれる(GPU待機済み)。
    pub(crate) fn 破棄する(&self, device: &ash::Device) {
        self.パイプライン.破棄する(device);
    }
}
