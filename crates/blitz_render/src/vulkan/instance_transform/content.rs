//! 個体1件ぶんの変換と、それに対応する法線行列。頂点シェーダーが`SV_InstanceID`で1件を参照する単位である。
//! 個体が1体だけの対象も1件の列としてこの内容を並べるため、単一個体のための別の配置は存在しない。
//! 注意: この構造の並びはシェーダーの`InstanceTransform`と1対1で対応する。並びを変えると全対象が壊れた行列で描かれる。

use blitz_math::{ローカル, ワールド, 位置, 変換};
use glam::{Mat3, Mat4};

use crate::error::レンダラーエラー;
use crate::frame_input::読込時の向きから天頂軸まわりに回す角;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 個体変換内容 {
    pub(crate) ローカルからワールド: [[f32; 4]; 4],
    pub(crate) 法線ローカルからワールド: [[f32; 3]; 3],
}

impl 個体変換内容 {
    /// 法線行列は変換の線形部の逆転置である。行列式が0に近い変換は法線を求められないため、無言で単位行列へ落とさず型付きエラーにする。
    pub(crate) fn 変換から作る(ローカルからワールド: 変換<ローカル, ワールド>) -> Result<Self, レンダラーエラー> {
        let 生行列 = ローカルからワールド.gpu境界用列優先配列();
        let 法線基底 = Mat3::from_mat4(Mat4::from_cols_array_2d(&生行列));
        let 行列式 = 法線基底.determinant();
        if !行列式.is_finite() || 行列式.abs() <= f32::EPSILON {
            return Err(レンダラーエラー::描画対象変換非可逆);
        }
        Ok(Self {
            ローカルからワールド: 生行列,
            法線ローカルからワールド: 法線基底.inverse().transpose().to_cols_array_2d(),
        })
    }

    /// 読込時の姿勢から天頂軸まわりに回し、平行移動の成分を差し替えた内容を返す。動く個体の毎フレームの書き込みが、
    /// 読込時の寸法を保ったまま位置と向きを動かすために使う。
    ///
    /// 注意: 行列は列優先であり、4本目の列が平行移動である。並びを変えると動く個体が読込時の位置から動かなくなるか、
    /// 向きが毎フレーム壊れる。回転を線形部へ左から掛けるのは、読込時の変換でローカルからワールドへ移した後に
    /// ワールドの天頂軸まわりで回すためである。右から掛けるとモデルの傾いた軸まわりに回る。
    /// 法線行列は線形部の逆転置であり、回転行列は直交であるためその逆転置は同じ回転になる。同じ回転を左から掛ければ足りる。
    pub(crate) fn 天頂軸まわりに回して平行移動成分を置き換えた内容を返す(
        &self,
        回す角: 読込時の向きから天頂軸まわりに回す角,
        基準原点からの相対位置: 位置<ワールド>,
    ) -> Self {
        let 回転 = Mat3::from_rotation_y(回す角.ラジアンで表した角().値());
        let 回した線形部 = (回転 * Mat3::from_mat4(Mat4::from_cols_array_2d(&self.ローカルからワールド))).to_cols_array_2d();
        let mut 差し替え後 = *self;
        for (列番号, 回した列) in 回した線形部.iter().enumerate() {
            差し替え後.ローカルからワールド[列番号] = [回した列[0], 回した列[1], 回した列[2], self.ローカルからワールド[列番号][3]];
        }
        差し替え後.ローカルからワールド[3] = [
            基準原点からの相対位置.x().値(),
            基準原点からの相対位置.y().値(),
            基準原点からの相対位置.z().値(),
            1.0,
        ];
        差し替え後.法線ローカルからワールド = (回転 * Mat3::from_cols_array_2d(&self.法線ローカルからワールド)).to_cols_array_2d();
        差し替え後
    }

    /// 描画対象1つぶんの全個体の変換をGPUへ載せる形へ直す。1件でも複数件でも同じ経路を通るため、
    /// 個体数で確保の仕方が変わらない。
    pub(crate) fn 一覧を作る(変換一覧: &[変換<ローカル, ワールド>]) -> Result<Vec<Self>, レンダラーエラー> {
        変換一覧.iter().map(|変換| Self::変換から作る(*変換)).collect()
    }
}
