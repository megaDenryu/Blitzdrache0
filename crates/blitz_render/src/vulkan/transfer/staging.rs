//! ステージング用のホスト可視バッファを介して、ホストとGPUの間でバイト列を移す係。確保係と転送実行環境を
//! コンストラクタ注入で保持し、移す向きごとにメソッドを公開する。
//!
//! 2つを1つの型へまとめるのは、どちらか片方だけでは1回の受け渡しが完結しないためである。確保だけでは中身が入らず、
//! 転送だけでは送り元と受け皿が無い。別々の引数で運ばせると、受け渡しを頼む階層すべての署名にGPUの依存が2つ並ぶ。
//! 検収だけが通る読み戻しの向きは`word_readback`が持つ。参照: _doc/計画/ユビキタス言語.md「操作サービス」

mod word_readback;

use ash::vk;

use super::転送実行環境;
use crate::error::レンダラーエラー;
use crate::vulkan::allocator::{GPU資源の確保係, 専用メモリ付きバッファ};
use crate::vulkan::command_sink::積み込みを開始したコマンドバッファ;
use crate::vulkan::tracked_device::GPUデバイス;

#[derive(Clone, Copy)]
pub(crate) struct ステージング経由の転送係<'借用> {
    確保係: &'借用 GPU資源の確保係<'借用>,
    転送環境: &'借用 転送実行環境,
}

impl<'借用> ステージング経由の転送係<'借用> {
    pub(crate) const fn 生成する(確保係: &'借用 GPU資源の確保係<'借用>, 転送環境: &'借用 転送実行環境) -> Self {
        Self { 確保係, 転送環境 }
    }

    /// 受け渡しを伴わない確保だけを頼む階層へ貸す口。返る参照が借りるのは元の`GPU環境`であり、この係ではない。
    pub(crate) const fn 確保係(&self) -> &'借用 GPU資源の確保係<'借用> {
        self.確保係
    }

    /// 受け渡しでなく命令の送信だけを頼む階層へ貸す口。GPU上での消去のように、ホスト側のバイト列を伴わない操作が使う。
    pub(crate) const fn 転送環境(&self) -> &'借用 転送実行環境 {
        self.転送環境
    }

    pub(crate) fn 論理デバイス(&self) -> &'借用 GPUデバイス {
        self.確保係.論理デバイス()
    }

    /// ホスト側のバイト列と同じ長さのデバイスローカルバッファを確保し、ステージングを経由して中身を書き込む
    /// (判断20: 頂点/インデックス共通の転送基盤)。
    pub(crate) fn データからデバイスローカルバッファを確保する(
        &self,
        データ: &[u8],
        用途: vk::BufferUsageFlags,
    ) -> Result<専用メモリ付きバッファ, レンダラーエラー> {
        let ステージング = self
            .確保係
            .ホスト可視バッファを確保して書き込む(データ, vk::BufferUsageFlags::TRANSFER_SRC)?;
        let バイト数 = u64::try_from(データ.len()).unwrap_or_else(|_| panic!("転送データ長がu64に収まらない"));
        let 転送先 = match self
            .確保係
            .デバイスローカルバッファを確保する(バイト数, 用途 | vk::BufferUsageFlags::TRANSFER_DST)
        {
            Ok(転送先) => 転送先,
            Err(誤り) => {
                ステージング.破棄する(self.論理デバイス());
                return Err(誤り);
            }
        };

        let コピー結果 = self.バッファ間をコピーする(ステージング.バッファのハンドル(), 転送先.バッファのハンドル(), バイト数);
        ステージング.破棄する(self.論理デバイス());
        if let Err(誤り) = コピー結果 {
            転送先.破棄する(self.論理デバイス());
            return Err(誤り);
        }
        Ok(転送先)
    }

    /// 前提: コピー長は送り元と受け皿の確保長以下である。
    fn バッファ間をコピーする(&self, 元: vk::Buffer, 先: vk::Buffer, バイト数: u64) -> Result<(), レンダラーエラー> {
        let 一時 = self.転送環境.転送コマンドを積み始める()?;
        let 領域 = [vk::BufferCopy::default().size(バイト数)];
        // 安全性: command_bufferは積み込み開始済みで、コピー長は前提により両バッファの確保長以下である。
        let 積み先 = 一時.積み先();
        unsafe { 積み先.論理デバイス().cmd_copy_buffer(積み先.コマンドバッファ(), 元, 先, &領域) };
        一時.送信して完了を待つ()
    }
}
