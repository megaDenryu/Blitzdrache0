//! 進行中フレームのスロットを指す添字。フェンス・取得セマフォ・コマンドバッファ・フレームシェーダー定数・
//! スキン行列・布の介入と定数・UI ジオメトリ・GPU計測プールは、いずれもこの添字で参照する要素数`進行中フレーム数`の配列である。
//! 値を作る手段を先頭・次のスロット・全スロットの3つに限るため、範囲外の値を作れず範囲検証も要らない。
//!
//! 注意: スワップチェーン画像添字とは値の範囲が重なるため、両方を生の整数で扱うと入れ替えても添字が範囲内に収まり、
//! 別のスロットの資源を参照したまま描画が成立する。別型にすることで入れ替えをコンパイルエラーにする。
//! 参照: crates/blitz_render/src/vulkan/swapchain/image_index.rs がもう一方の添字型を持つ。

#[cfg(test)]
mod frame_slot_index_tests;

use super::進行中フレーム数;

#[derive(Clone, Copy)]
#[repr(transparent)]
pub(crate) struct フレームスロット添字 {
    値: usize,
}

impl フレームスロット添字 {
    /// 巡回の開始位置。フレーム進行の巡回だけがここから始める。
    pub(crate) const fn 先頭() -> Self {
        Self { 値: 0 }
    }

    /// 巡回の次の位置。`進行中フレーム数`で折り返すため範囲を出ない。
    pub(crate) const fn 次のスロット(self) -> Self {
        Self {
            値: (self.値 + 1) % 進行中フレーム数,
        }
    }

    /// 全スロットへ同じ初期設定を書き込む生成時の走査に使う。毎フレームの描画経路では使わない。
    pub(crate) fn 全スロット() -> [Self; 進行中フレーム数] {
        std::array::from_fn(|値| Self { 値 })
    }

    /// GPU境界: 進行中フレーム分の配列を参照する生の添字へ戻す。
    pub(crate) const fn 配列添字(self) -> usize {
        self.値
    }
}
