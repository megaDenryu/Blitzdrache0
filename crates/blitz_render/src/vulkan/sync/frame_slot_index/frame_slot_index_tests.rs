use super::フレームスロット添字;
use crate::vulkan::sync::進行中フレーム数;

#[test]
fn 先頭は0を指す() {
    assert_eq!(フレームスロット添字::先頭().配列添字(), 0);
}

#[test]
fn 次のスロットは進行中フレーム数で折り返す() {
    let mut スロット = フレームスロット添字::先頭();
    for _ in 0..進行中フレーム数 {
        スロット = スロット.次のスロット();
    }
    assert_eq!(スロット.配列添字(), 0);
}

#[test]
fn 次のスロットは常に範囲内に収まる() {
    let mut スロット = フレームスロット添字::先頭();
    for _ in 0..進行中フレーム数 * 3 + 1 {
        スロット = スロット.次のスロット();
        assert!(スロット.配列添字() < 進行中フレーム数);
    }
}

#[test]
fn 全スロットは0から順に重複なく並ぶ() {
    let 添字一覧: Vec<usize> = フレームスロット添字::全スロット().iter().map(|スロット| スロット.配列添字()).collect();
    assert_eq!(添字一覧, (0..進行中フレーム数).collect::<Vec<usize>>());
}
