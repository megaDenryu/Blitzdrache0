//! そのフレームに影を落とす灯の並びを、カメラ相対の座標へ狭めた形で持つ値。触れるのは灯の並びだけであり、
//! 描画の順序も資源も知らない。
//!
//! 局所光源列が完成させた1つの割り当てをここへ写す。レコードの書き込みと面ごとの描画パスが別々に宣言から
//! 添字を導き直すと、レコードの影資源添字が指す立方体と描いた立方体が食い違いうる
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断k」)。
//!
//! 固定長の枠で持つのは、毎フレームのヒープ確保を作らないためである。上限は影を持てる灯の件数と同じである。

use blitz_math::{ワールド, 位置, 大域ワールド位置, 座標変換エラー};

use crate::clustered_lighting::影響半径;
use crate::lighting_input::局所光源列;
use crate::point_light_shadow::{影を持てる灯の上限件数, 影資源添字, 投影の契約};

/// 影を落とす灯1件ぶんの、面ごとの描画パスが要る値。
#[derive(Debug, Clone, Copy)]
pub(crate) struct 影を落とす灯 {
    pub(crate) 影資源添字: 影資源添字,
    /// 描く対象と同じカメラ大域原点で狭めた灯の位置。
    pub(crate) カメラ相対位置: 位置<ワールド>,
    pub(crate) 影響半径: 影響半径,
    pub(crate) 投影の契約: 投影の契約,
}

/// そのフレームの影の描画計画。件数0の世界も同じ型で表し、影を持たないことを別の状態にしない。
#[derive(Debug, Clone, Copy)]
pub(crate) struct 点光源の影の描画計画 {
    枠: [Option<影を落とす灯>; 影を持てる灯の上限件数],
}

impl 点光源の影の描画計画 {
    /// 局所光源列の割り当てを、そのフレームのカメラ大域原点で狭める。狭めに失敗したら型付きの失敗にする
    /// (黙って灯を落とすと、影がその灯だけ消えた絵の原因を入力から読めなくなる)。
    pub(crate) fn 局所光源列から生成する(
        局所光源列: 局所光源列, カメラ大域原点: 大域ワールド位置
    ) -> Result<Self, 座標変換エラー> {
        let mut 枠 = [None; 影を持てる灯の上限件数];
        for (添字, (影資源添字, 点光源, 投影の契約)) in 局所光源列.影の描画計画を宣言の順に返す().enumerate() {
            let カメラ相対位置 = 点光源.位置().局所ワールド位置へ狭める(カメラ大域原点)?;
            枠[添字] = Some(影を落とす灯 {
                影資源添字,
                カメラ相対位置,
                影響半径: 点光源.影響半径(),
                投影の契約,
            });
        }
        Ok(Self { 枠 })
    }

    /// 影を落とす灯の件数。0なら面ごとの描画パスを1本も積まず、絞りの判定も1度も行わない。
    pub(crate) fn 灯の件数(&self) -> usize {
        self.枠.iter().flatten().count()
    }

    pub(crate) fn 灯を宣言の順に返す(&self) -> impl Iterator<Item = 影を落とす灯> + '_ {
        self.枠.iter().flatten().copied()
    }
}
