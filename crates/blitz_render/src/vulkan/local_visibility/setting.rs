//! 局所可視性補正の2つのコンピュートが押し込む即時定数の並び。受け取るのは射影の復元・画面寸法・
//! 局所可視性の設定であり、返すのはそのままGPUへ渡せるバイト列である。
//!
//! 並びの正本は`shaders/local_visibility_setting.slang`の`LocalVisibilitySetting`であり、この工程はその写しを
//! 1箇所へ閉じる。2つのエントリが同じ並びを押し込むのは、遮蔽の標本化とぼかしが同じ射影と同じ寸法を読むためである。
//! 片方だけ別の並びにすると、同じ画面を別の射影で解釈した2枚が重なる。

use ash::vk;

use crate::local_visibility::{射影の復元, 局所可視性の設定};

#[cfg(test)]
mod layout_tests;

/// 押し込む定数のバイト数。単精度12個と符号なし整数4個の並びである。
pub(crate) const 即時定数バイト数: u32 = 64;

/// 即時定数の並びを組み立てる。
pub(crate) fn 即時定数を組み立てる(射影: 射影の復元, 寸法: vk::Extent2D, 設定: 局所可視性の設定) -> Vec<u8> {
    let 遮蔽 = 設定.遮蔽();
    let ぼかし = 設定.ぼかし();
    let mut バイト列 = Vec::with_capacity(usize::try_from(即時定数バイト数).unwrap_or(0));
    単精度を足す(&mut バイト列, 射影.近クリップ().値());
    単精度を足す(&mut バイト列, 射影.遠クリップ().値());
    単精度を足す(&mut バイト列, 射影.縦視野角の半角の正接());
    単精度を足す(&mut バイト列, 射影.横縦比());
    単精度を足す(&mut バイト列, 射影.画素内ずらし().正規化装置座標の横());
    単精度を足す(&mut バイト列, 射影.画素内ずらし().正規化装置座標の縦());
    整数を足す(&mut バイト列, 寸法.width);
    整数を足す(&mut バイト列, 寸法.height);
    単精度を足す(&mut バイト列, 遮蔽.半径().長さ().値());
    単精度を足す(&mut バイト列, 遮蔽.深度バイアス().倍率());
    単精度を足す(&mut バイト列, 遮蔽.距離減衰().重みを保つ倍率());
    単精度を足す(&mut バイト列, 遮蔽.距離減衰().重みが尽きる倍率());
    整数を足す(&mut バイト列, 遮蔽.標本数().値());
    単精度を足す(&mut バイト列, 遮蔽.同一面の許容().値());
    整数を足す(&mut バイト列, ぼかし.画素半径());
    単精度を足す(&mut バイト列, ぼかし.同じ面と認める許容().値());
    バイト列
}

fn 単精度を足す(バイト列: &mut Vec<u8>, 値: f32) {
    バイト列.extend_from_slice(&値.to_le_bytes());
}

fn 整数を足す(バイト列: &mut Vec<u8>, 値: u32) {
    バイト列.extend_from_slice(&値.to_le_bytes());
}
