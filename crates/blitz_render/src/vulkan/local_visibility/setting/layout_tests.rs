//! 即時定数の並びが`shaders/local_visibility_setting.slang`の宣言と同じ長さ・同じ位置になることの検査。
//! シェーダー側の構造体を読めないため、位置ごとに違う値を入れて読み出す形で固定する。
//! 位置が1つずれると、遮蔽の半径がぼかしの窓として読まれるような取り違えが絵にだけ現れる。

#![allow(clippy::unwrap_used)]

use ash::vk;
use blitz_math::{メートル, ラジアン, 画素内ずらし};

use super::{即時定数を組み立てる, 即時定数バイト数};
use crate::local_visibility::{射影の復元, 局所可視性の設定};

fn 単精度を読む(バイト列: &[u8], 位置: usize) -> f32 {
    f32::from_le_bytes(バイト列[位置..位置 + 4].try_into().unwrap())
}

fn 整数を読む(バイト列: &[u8], 位置: usize) -> u32 {
    u32::from_le_bytes(バイト列[位置..位置 + 4].try_into().unwrap())
}

fn ずらし() -> 画素内ずらし {
    画素内ずらし::画素から生成する(0.25, -0.25, 1280, 720).unwrap()
}

fn 組み立てる() -> Vec<u8> {
    let 射影 = 射影の復元::生成する(
        メートル::生成する(0.25),
        メートル::生成する(400.0),
        ラジアン::度から(60.0),
        16.0 / 9.0,
        ずらし(),
    )
    .unwrap();
    let 寸法 = vk::Extent2D { width: 1280, height: 720 };
    即時定数を組み立てる(射影, 寸法, 局所可視性の設定::既定())
}

#[test]
fn 即時定数の長さは宣言したバイト数と一致する() {
    assert_eq!(組み立てる().len(), usize::try_from(即時定数バイト数).unwrap());
}

#[test]
fn 射影の6つと画面寸法が先頭に並ぶ() {
    let バイト列 = 組み立てる();
    assert_eq!(単精度を読む(&バイト列, 0), 0.25);
    assert_eq!(単精度を読む(&バイト列, 4), 400.0);
    assert_eq!(単精度を読む(&バイト列, 8), (ラジアン::度から(60.0).値() * 0.5).tan());
    assert_eq!(単精度を読む(&バイト列, 12), 16.0 / 9.0);
    assert_eq!(単精度を読む(&バイト列, 16), ずらし().正規化装置座標の横());
    assert_eq!(単精度を読む(&バイト列, 20), ずらし().正規化装置座標の縦());
    assert_eq!(整数を読む(&バイト列, 24), 1280);
    assert_eq!(整数を読む(&バイト列, 28), 720);
}

#[test]
fn 遮蔽の5つとぼかしの2つが射影と寸法の後ろに並ぶ() {
    let バイト列 = 組み立てる();
    let 既定 = 局所可視性の設定::既定();
    assert_eq!(単精度を読む(&バイト列, 32), 既定.遮蔽().半径().長さ().値());
    assert_eq!(単精度を読む(&バイト列, 36), 既定.遮蔽().深度バイアス().倍率());
    assert_eq!(単精度を読む(&バイト列, 40), 既定.遮蔽().距離減衰().重みを保つ倍率());
    assert_eq!(単精度を読む(&バイト列, 44), 既定.遮蔽().距離減衰().重みが尽きる倍率());
    assert_eq!(整数を読む(&バイト列, 48), 既定.遮蔽().標本数().値());
    assert_eq!(単精度を読む(&バイト列, 52), 既定.遮蔽().同一面の許容().値());
    assert_eq!(整数を読む(&バイト列, 56), 既定.ぼかし().画素半径());
    assert_eq!(単精度を読む(&バイト列, 60), 既定.ぼかし().同じ面と認める許容().値());
}
