//! 画面寸法の変更への追従。2枚の可視度画像を作り直し、描画設定が答える符号値で埋め直し、セットを新しい画像と新しい深度へ結び直す。
//! 呼び出しタイミング: リサイズ・陳腐化でスワップチェーンを作り直した直後(GPU待機済み)。
//!
//! 新しい画像を作ってから古い画像を破棄するため、画像生成が失敗しても呼び出し前の一式がそのまま残り、
//! 保持側は一部だけが欠けた状態を見ない。交換の間だけ新旧の画像が同時に存在する分のGPUメモリを使う。
//!
//! 埋め直しを落とせないのは、確保したばかりの画像の中身が不定だからである。パスを1本も積まない実行では
//! この工程が書いた符号値だけが拡散間接照度への乗数になる。

use ash::vk;

use super::{fill, images::局所可視度の画像組, 局所可視性一式};
use crate::error::レンダラーエラー;
use crate::vulkan::tracked_device::GPUデバイス;
use crate::vulkan::transfer::転送実行環境;

impl 局所可視性一式 {
    /// 前提: 呼び出し時点でGPUがこれらの画像とディスクリプタを使用していないこと(device_wait_idle後)。
    /// 深度ビューは作り直された後の新しいものを渡す。
    pub(crate) fn 寸法に追従する(
        &mut self,
        device: &GPUデバイス,
        メモリプロパティ: &vk::PhysicalDeviceMemoryProperties,
        転送環境: &転送実行環境,
        寸法: vk::Extent2D,
        深度ビュー: vk::ImageView,
    ) -> Result<(), レンダラーエラー> {
        let 新画像組 = 局所可視度の画像組::生成する(device, メモリプロパティ, 寸法)?;
        if let Err(誤り) = fill::一定の符号値で埋める(device, 転送環境, &新画像組, self.描画設定.埋める符号値()) {
            新画像組.破棄する(device);
            return Err(誤り);
        }
        // 注意: 旧画像の破棄は、それを読んでいたディスクリプタを新画像へ差し替えた後に行う。
        let 旧画像組 = std::mem::replace(&mut self.画像組, 新画像組);
        self.資源を束縛する(device, 深度ビュー);
        旧画像組.破棄する(device);
        Ok(())
    }
}
