//! 多段影定数をバイト列へ組み立てる工程。受け取るのは定数内容、返すのは
//! shaders/cascade_shadow_uniform.slangのCascadeShadowUniformと同じ並びのバイト列である。
//!
//! 注意: 並びはシェーダー側の宣言順と完全に一致させること。ここを崩すと値化けとして現れる。

use super::cascade_content::多段影定数内容;
use super::write_bytes::{vec4を書き込む, ベクトル3をvec4化, 真偽を数にする, 行列を書き込む};

/// バイト長: 行列4つ(距離区分ごとのライトビュー射影。256) + vec4単位3個(48) = 304。
pub(crate) const バイト長: usize = 256 + 48;

pub(super) fn バイト列にする(内容: &多段影定数内容) -> [u8; バイト長] {
    let mut バイト列 = [0u8; バイト長];
    let mut 位置 = 0usize;

    for 行列 in 内容.距離区分のライトビュー射影行列 {
        行列を書き込む(&mut バイト列, &mut 位置, 行列);
    }
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.距離区分の分割深度, 0.0));
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.距離区分の遷移幅, 0.0));
    vec4を書き込む(
        &mut バイト列,
        &mut 位置,
        [
            真偽を数にする(内容.影を落とす),
            真偽を数にする(内容.距離区分を可視化する),
            内容.シャドウマップのテクセル尺度,
            0.0,
        ],
    );
    バイト列
}
