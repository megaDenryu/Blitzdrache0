//! 3本のシェーダー定数それぞれについて、CPU側のバイト長と全フィールドの開始位置を数値で固定する検査。
//! シェーダー側の宣言との一致は`shader_struct_tests`が別に見る。ここが崩れると値化けとして絵に出る。

use super::{cascade_bytes, sky_bytes, view_pass_bytes};
use super::{ビューとシーンパスの定数内容, 多段影定数内容, 空パス定数内容};

#[test]
fn ビューとシーンパスの定数の各値が決めた開始位置へ並ぶ() {
    let 内容 = ビューとシーンパスの定数内容 {
        ビュー射影行列: [[10.0, 0.0, 0.0, 0.0], [0.0; 4], [0.0; 4], [0.0; 4]],
        カメラ相対位置: [20.0, 21.0, 22.0],
        カメラ前方: [100.0, 101.0, 102.0],
        方向光方向: [30.0, 31.0, 32.0],
        方向光色: [40.0, 41.0, 42.0],
        方向光強度: 43.0,
        点光源位置: [50.0, 51.0, 52.0],
        点光源色: [60.0, 61.0, 62.0],
        点光源強度: 63.0,
        環境光係数: 70.0,
        ライティング有効: true,
    };
    let バイト列 = view_pass_bytes::バイト列にする(&内容);
    assert_eq!(バイト列.len(), 176);
    assert_eq!(f32を読む(&バイト列, 0), 10.0);
    assert_eq!(f32を読む(&バイト列, 64), 20.0);
    assert_eq!(f32を読む(&バイト列, 80), 100.0);
    assert_eq!(f32を読む(&バイト列, 96), 30.0);
    assert_eq!(f32を読む(&バイト列, 112), 40.0);
    assert_eq!(f32を読む(&バイト列, 124), 43.0);
    assert_eq!(f32を読む(&バイト列, 128), 50.0);
    assert_eq!(f32を読む(&バイト列, 144), 60.0);
    assert_eq!(f32を読む(&バイト列, 156), 63.0);
    assert_eq!(f32を読む(&バイト列, 160), 70.0);
    assert_eq!(f32を読む(&バイト列, 164), 1.0);
}

#[test]
fn 多段影定数の各値が決めた開始位置へ並ぶ() {
    let 距離区分の行列 = std::array::from_fn(|添字| {
        let mut 行列 = [[0.0_f32; 4]; 4];
        行列[0][0] = f32::from(u8::try_from(添字 + 1).unwrap_or(1));
        行列
    });
    let 内容 = 多段影定数内容 {
        距離区分のライトビュー射影行列: 距離区分の行列,
        距離区分の分割深度: [80.0, 81.0, 82.0],
        距離区分の遷移幅: [90.0, 91.0, 92.0],
        影を落とす: false,
        距離区分を可視化する: true,
        シャドウマップのテクセル尺度: 0.000_488_281_25,
    };
    let バイト列 = cascade_bytes::バイト列にする(&内容);
    assert_eq!(バイト列.len(), 304);
    for 添字 in 0..crate::cascade::距離区分数 {
        assert_eq!(f32を読む(&バイト列, 添字 * 64), f32::from(u8::try_from(添字 + 1).unwrap_or(1)));
    }
    assert_eq!(f32を読む(&バイト列, 256), 80.0);
    assert_eq!(f32を読む(&バイト列, 272), 90.0);
    assert_eq!(f32を読む(&バイト列, 288), 0.0);
    assert_eq!(f32を読む(&バイト列, 292), 1.0);
    assert_eq!(f32を読む(&バイト列, 296), 0.000_488_281_25);
}

#[test]
fn 空パス定数の各値が決めた開始位置へ並ぶ() {
    let 内容 = 空パス定数内容 {
        逆ビュー射影行列: [[200.0, 0.0, 0.0, 0.0], [0.0; 4], [0.0; 4], [0.0; 4]],
        夜空放射輝度: [111.0, 112.0, 113.0],
        太陽円盤の余弦角半径: 114.0,
        太陽方向: [121.0, 122.0, 123.0],
        観測高度: 124.0,
        太陽円盤放射輝度: [131.0, 132.0, 133.0],
        太陽放射照度: 134.0,
    };
    let バイト列 = sky_bytes::バイト列にする(&内容);
    assert_eq!(バイト列.len(), 112);
    assert_eq!(f32を読む(&バイト列, 0), 200.0);
    assert_eq!(f32を読む(&バイト列, 64), 111.0);
    assert_eq!(f32を読む(&バイト列, 76), 114.0);
    assert_eq!(f32を読む(&バイト列, 80), 121.0);
    assert_eq!(f32を読む(&バイト列, 92), 124.0);
    assert_eq!(f32を読む(&バイト列, 96), 131.0);
    assert_eq!(f32を読む(&バイト列, 108), 134.0);
}

fn f32を読む(バイト列: &[u8], 位置: usize) -> f32 {
    let 配列 = match バイト列[位置..位置 + 4].try_into() {
        Ok(配列) => 配列,
        Err(_) => panic!("4バイトの切り出しに失敗した"),
    };
    f32::from_le_bytes(配列)
}
