//! `フレームユニフォーム内容`をFrameUniform(shaders/scene.slang)と一致する
//! 224バイトのバイト列へ組み立てる。成分ごとの`to_le_bytes`で行い、
//! ポインタ再解釈には依存しない(vulkan/geometry/bytes.rsと同じ方針)。
//!
//! 注意: ライトビュー射影行列を先頭(オフセット0)に置く。シャドウパス
//! (shaders/shadow.slang)は同じbinding3を「先頭に光源ビュー射影行列だけを
//! 持つ構造体」として解釈するため、先頭フィールドの一致が同期の前提になる。

use super::content::フレームユニフォーム内容;

/// UBO全体のバイト長: 行列2つ(128) + vec4単位6個(96) = 224。
pub(super) const バイト長: usize = 224;

pub(super) fn バイト列にする(内容: &フレームユニフォーム内容) -> [u8; バイト長] {
    let mut バイト列 = [0u8; バイト長];
    let mut 位置 = 0usize;

    行列を書き込む(&mut バイト列, &mut 位置, 内容.ライトビュー射影行列);
    行列を書き込む(&mut バイト列, &mut 位置, 内容.ビュー射影行列);
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.カメラワールド位置, 0.0));
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.方向光方向, 0.0));
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.方向光色, 内容.方向光強度));
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.点光源位置, 0.0));
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.点光源色, 内容.点光源強度));
    let ライティング有効値 = if 内容.ライティング有効 { 1.0 } else { 0.0 };
    vec4を書き込む(&mut バイト列, &mut 位置, [内容.環境光係数, ライティング有効値, 0.0, 0.0]);
    バイト列
}

fn 行列を書き込む(バイト列: &mut [u8; バイト長], 位置: &mut usize, 行列: [[f32; 4]; 4]) {
    for 列 in 行列 {
        vec4を書き込む(バイト列, 位置, 列);
    }
}

fn vec4を書き込む(バイト列: &mut [u8; バイト長], 位置: &mut usize, 値: [f32; 4]) {
    for 成分 in 値 {
        バイト列[*位置..*位置 + 4].copy_from_slice(&成分.to_le_bytes());
        *位置 += 4;
    }
}

fn ベクトル3をvec4化(ベクトル: [f32; 3], w: f32) -> [f32; 4] {
    [ベクトル[0], ベクトル[1], ベクトル[2], w]
}
