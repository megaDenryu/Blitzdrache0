//! `フレームユニフォーム内容`をFrameUniform(shaders/scene.slang)と一致するバイト列へ組み立てる。
//! 成分ごとの`to_le_bytes`で行い、ポインタ再解釈には依存しない(vulkan/geometry/bytes.rsと同じ方針)。
//! 前半464バイトがシーンとシャドウが読む区画、後半272バイトが空パスだけが読む区画である。
//! 後半の並べ方は`sky_bytes`が持つ。
//!
//! 注意: 帯ごとのライトビュー射影行列の配列を先頭(オフセット0)に置く。シャドウパス
//! (shaders/shadow.slang・shaders/cloth_shadow.slang)は同じbinding3を「先頭に帯ごとの
//! 光源ビュー射影行列の配列だけを持つ構造体」として解釈するため、先頭フィールドの一致が同期の前提になる。

use super::content::フレームユニフォーム内容;
use super::sky_bytes;

/// シーンとシャドウが読む区画のバイト長: 行列5つ(帯4つ + ビュー射影。320) + vec4単位9個(144) = 464。
const 共通区画バイト長: usize = 320 + 144;
/// UBO全体のバイト長。
pub(super) const バイト長: usize = 共通区画バイト長 + super::sky_bytes::空区画バイト長;

pub(super) fn バイト列にする(内容: &フレームユニフォーム内容) -> [u8; バイト長] {
    let mut バイト列 = [0u8; バイト長];
    let mut 位置 = 0usize;

    for 行列 in 内容.帯ライトビュー射影行列 {
        行列を書き込む(&mut バイト列, &mut 位置, 行列);
    }
    行列を書き込む(&mut バイト列, &mut 位置, 内容.ビュー射影行列);
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.カメラ相対位置, 0.0));
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.方向光方向, 0.0));
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.方向光色, 内容.方向光強度));
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.点光源位置, 0.0));
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.点光源色, 内容.点光源強度));
    let ライティング有効値 = if 内容.ライティング有効 { 1.0 } else { 0.0 };
    let 影を落とす値 = if 内容.影を落とす { 1.0 } else { 0.0 };
    vec4を書き込む(&mut バイト列, &mut 位置, [内容.環境光係数, ライティング有効値, 影を落とす値, 0.0]);
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.帯分割深度, 0.0));
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.帯遷移幅, 0.0));
    let 帯可視化値 = if 内容.カスケード帯を可視化する { 1.0 } else { 0.0 };
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.カメラ前方, 帯可視化値));
    sky_bytes::書き込む(&mut バイト列, &mut 位置, &内容.空);
    バイト列
}

pub(super) fn 行列を書き込む(バイト列: &mut [u8], 位置: &mut usize, 行列: [[f32; 4]; 4]) {
    for 列 in 行列 {
        vec4を書き込む(バイト列, 位置, 列);
    }
}

pub(super) fn vec4を書き込む(バイト列: &mut [u8], 位置: &mut usize, 値: [f32; 4]) {
    for 成分 in 値 {
        バイト列[*位置..*位置 + 4].copy_from_slice(&成分.to_le_bytes());
        *位置 += 4;
    }
}

pub(super) fn ベクトル3をvec4化(ベクトル: [f32; 3], w: f32) -> [f32; 4] {
    [ベクトル[0], ベクトル[1], ベクトル[2], w]
}
