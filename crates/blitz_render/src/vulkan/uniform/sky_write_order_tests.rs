//! 空パス定数をどのフレームで書くかの検査。空段階の無いフレーム構成では書込回数が0であり、
//! 空段階のあるフレーム構成では毎フレームちょうど1回であることを、画素でなく指示の数で確かめる。

use super::sky_write_order::{決める, 空パス定数の書込指示};
use crate::frame_input::{空入力, 空入力の材料};

const フレーム数: usize = 5;

#[test]
fn 空段階の無いフレーム構成では1回も書かない() {
    assert_eq!(書込回数を数える(false, None), 0);
}

#[test]
fn 空段階のあるフレーム構成では毎フレーム1回書く() {
    let 入力 = 空入力を作る();
    assert_eq!(書込回数を数える(true, Some(&入力)), フレーム数);
}

#[test]
fn 空段階と空入力の食い違いは型付きエラーになる() {
    let 入力 = 空入力を作る();
    assert!(決める(true, None).is_err());
    assert!(決める(false, Some(&入力)).is_err());
}

fn 書込回数を数える(空を描くか: bool, 入力: Option<&空入力>) -> usize {
    let mut 回数 = 0usize;
    for _ in 0..フレーム数 {
        match 決める(空を描くか, 入力) {
            Ok(空パス定数の書込指示::書き込む(_)) => 回数 += 1,
            Ok(空パス定数の書込指示::書き込まない) => {}
            Err(誤り) => panic!("書込指示を決められない: {誤り}"),
        }
    }
    回数
}

fn 空入力を作る() -> 空入力 {
    let 材料 = 空入力の材料 {
        夜空放射輝度: [0.001, 0.001, 0.002],
        太陽方向: [0.0, 1.0, 0.0],
        太陽円盤放射輝度: [1.0, 1.0, 1.0],
        太陽円盤角半径: blitz_math::ラジアン::生成する(0.004_65),
        観測高度: blitz_math::メートル::生成する(0.0),
        太陽放射照度: 1.0,
    };
    match 空入力::生成する(材料) {
        Ok(入力) => 入力,
        Err(誤り) => panic!("検査用の空入力を作れない: {誤り}"),
    }
}
