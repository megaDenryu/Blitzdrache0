//! ビュー定数をバイト列へ組み立てる工程。受け取るのは定数内容、返すのは
//! shaders/view_uniform.slangのViewUniformと同じ並びのバイト列である。
//!
//! 注意: 並びはシェーダー側の宣言順と完全に一致させること。ここを崩すと値化けとして現れる。

use super::view_content::ビュー定数内容;
use super::write_bytes::{vec4を書き込む, ベクトル3をvec4化, 行列を書き込む};

/// バイト長: 行列2つ(128) + vec4単位2個(32) = 160。
pub(crate) const バイト長: usize = 64 + 32 + 64;

pub(super) fn バイト列にする(内容: &ビュー定数内容) -> [u8; バイト長] {
    let mut バイト列 = [0u8; バイト長];
    let mut 位置 = 0usize;

    行列を書き込む(&mut バイト列, &mut 位置, 内容.ビュー射影行列);
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.カメラ相対位置, 0.0));
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.カメラ前方, 0.0));
    行列を書き込む(&mut バイト列, &mut 位置, 内容.前フレームのビュー射影行列);
    バイト列
}
