//! シャドウマップ用のライトビュー射影行列の組み立て(判断35・36)。
//! 光源位置から原点(シーン中心)を注視し、固定範囲の正射影で光源クリップ空間へ写す。

use blitz_math::{ビュー, メートル, ワールド, 位置, 光源クリップ, 変換};

use super::lighting_constants;

/// フレームユニフォームへ書き込む、ワールド→光源クリップのGPU境界用列優先配列。
/// シーンが変わっても光源・範囲は固定(判断35: カスケードなし・単一シャドウマップ)のため
/// カメラ姿勢に依存せず毎フレーム同じ値を返す。
pub(crate) fn ライトビュー射影行列() -> [[f32; 4]; 4] {
    let 光源位置生値 = lighting_constants::光源位置();
    let 光源位置 = 位置::<ワールド>::生成する(
        メートル::生成する(光源位置生値[0]),
        メートル::生成する(光源位置生値[1]),
        メートル::生成する(光源位置生値[2]),
    );
    let 原点 = 位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0));

    let ライトビュー変換 = 変換::注視(光源位置, 原点);
    let 半幅 = メートル::生成する(lighting_constants::シャドウ正射影半幅());
    let 正射影変換: 変換<ビュー, 光源クリップ> = 変換::正射影(
        半幅,
        半幅,
        メートル::生成する(lighting_constants::シャドウ近クリップ()),
        メートル::生成する(lighting_constants::シャドウ遠クリップ()),
    );

    ライトビュー変換.合成する(正射影変換).gpu境界用列優先配列()
}
