//! ビュー定数へ書き込む内容。全シーン描画が同じビューで読む小値だけを持つ。
//! std140/HLSL cbufferのどちらでも16バイト境界を跨がないよう、行列以外は全フィールドをvec4単位にそろえて
//! GPU側(shaders/view_uniform.slangのViewUniform)と1対1に対応させる(判断24)。
//!
//! 直接照明の値はここに無い。方向光と局所光は照明問い合わせのセットのレコード列が持つ
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「分離の形」)。
//!
//! 注意: フィールド順序はshaders/view_uniform.slangの宣言順と完全に一致させること。
//! ここを崩すと`view_bytes::バイト列にする`の開始位置がシェーダー側とずれ、値化けとして現れる。

pub(crate) struct ビュー定数内容 {
    pub(crate) ビュー射影行列: [[f32; 4]; 4],
    pub(crate) カメラ相対位置: [f32; 3],
    /// カメラの前方向(カメラ相対フレームの単位ベクトル)。ビュー空間深度を内積で求めるために渡す。
    pub(crate) カメラ前方: [f32; 3],
    /// 今フレームのカメラ大域原点で表し直した、前フレームのずらし無しビュー射影。動きベクトルの材料である。
    /// 参照: `_doc/設計/時間再構成.md`「判断b」
    pub(crate) 前フレームのビュー射影行列: [[f32; 4]; 4],
}
