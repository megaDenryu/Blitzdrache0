//! 空パス定数の内容。担当する工程は「空入力とビュー射影の逆行列を受け取り、
//! GPU側(shaders/sky_pass_uniform.slangのSkyPassUniform)と1対1に対応する値の束を作る」ことである。
//!
//! 空段階を持たないフレーム構成ではこの内容を1つも作らず、GPU側のバッファも書かない。
//! 書くか書かないかの判断は`sky_write_order`が持つ。
//!
//! 注意: フィールド順序はshaders/sky_pass_uniform.slangの宣言順と完全に一致させること。

use crate::frame_input::空入力;

pub(crate) struct 空パス定数内容 {
    pub(crate) 逆ビュー射影行列: [[f32; 4]; 4], // クリップ座標からカメラ相対ワールドへ戻す。全画面三角形の頂点から視線の向きを復元する
    pub(crate) 夜空放射輝度: [f32; 3],          // 太陽が地平線より下でも常時加算する夜間の背景放射輝度
    pub(crate) 太陽円盤の余弦角半径: f32,       // シェーダーは視線と太陽方向の内積をこの値と比べる
    pub(crate) 太陽方向: [f32; 3],
    pub(crate) 観測高度: f32, // スカイビューのベイク済み画像を焼いた観測点の地表からの高さ(メートル)
    pub(crate) 太陽円盤放射輝度: [f32; 3],
    pub(crate) 太陽放射照度: f32, // ベイク済み画像は放射照度1で焼くため、描画側がこの値を掛ける
}

impl 空パス定数内容 {
    pub(crate) fn 組み立てる(入力: &空入力, 逆ビュー射影行列: [[f32; 4]; 4]) -> Self {
        let 材料 = 入力.材料();
        Self {
            逆ビュー射影行列,
            夜空放射輝度: 材料.夜空放射輝度,
            太陽円盤の余弦角半径: 材料.太陽円盤角半径.値().cos(),
            太陽方向: 材料.太陽方向,
            観測高度: 材料.観測高度.値(),
            太陽円盤放射輝度: 材料.太陽円盤放射輝度,
            太陽放射照度: 材料.太陽放射照度,
        }
    }
}
