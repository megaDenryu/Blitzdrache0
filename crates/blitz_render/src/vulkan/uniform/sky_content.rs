//! フレームユニフォームの空の区画。担当する工程は「空入力とビュー射影の逆行列を受け取り、
//! GPU側(shaders/sky_frame.slangのSkyFrameUniform)の後半と1対1に対応する値の束を作る」ことである。
//!
//! 注意: 空段階を持たないフレーム構成でもこの区画は書く(全成分0)。UBOの全長を条件で変えると、
//! 同じバッファを読む他のシェーダーの記述と食い違うためである。0の区画を読むのは空パスだけであり、
//! そのパス自体が積まれないため絵には現れない。

use crate::frame_input::空入力;

pub(crate) struct 空ユニフォーム内容 {
    /// クリップ座標からカメラ相対ワールドへ戻す変換。全画面三角形の頂点から視線の向きを復元するために使う。
    pub(crate) 逆ビュー射影行列: [[f32; 4]; 4],
    /// 太陽が地平線より下でも常時加算する夜間の背景放射輝度。
    pub(crate) 夜空放射輝度: [f32; 3],
    /// 太陽円盤の角半径の余弦。シェーダーは視線と太陽方向の内積をこの値と比べる。
    pub(crate) 太陽円盤の余弦角半径: f32,
    pub(crate) 太陽方向: [f32; 3],
    /// スカイビューのベイク済み画像を焼いた観測点の地表からの高さ(メートル)。
    pub(crate) 観測高度: f32,
    pub(crate) 太陽円盤放射輝度: [f32; 3],
    /// 太陽の放射照度の尺度。ベイク済み画像は放射照度1で焼くため、描画側がこの値を掛ける。
    pub(crate) 太陽放射照度: f32,
}

impl 空ユニフォーム内容 {
    pub(crate) fn 組み立てる(入力: &空入力, 逆ビュー射影行列: [[f32; 4]; 4]) -> Self {
        let 材料 = 入力.材料();
        Self {
            逆ビュー射影行列,
            夜空放射輝度: 材料.夜空放射輝度,
            太陽円盤の余弦角半径: 材料.太陽円盤角半径.値().cos(),
            太陽方向: 材料.太陽方向,
            観測高度: 材料.観測高度.値(),
            太陽円盤放射輝度: 材料.太陽円盤放射輝度,
            太陽放射照度: 材料.太陽放射照度,
        }
    }

    /// 空段階を持たないフレーム構成で書く値。
    pub(crate) fn 空白() -> Self {
        Self {
            逆ビュー射影行列: [[0.0; 4]; 4],
            夜空放射輝度: [0.0; 3],
            太陽円盤の余弦角半径: 1.0,
            太陽方向: [0.0, 1.0, 0.0],
            観測高度: 0.0,
            太陽円盤放射輝度: [0.0; 3],
            太陽放射照度: 0.0,
        }
    }
}
