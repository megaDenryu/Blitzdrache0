//! GPUへ渡すバイト列へ値を詰める部品。担当する工程は「バイト列と書き込み位置を受け取り、
//! 行列1つ・vec4単位1つ・uvec4単位1つを詰めて位置を進める」ことであり、どの定数のどの並びかは知らない。
//! 成分ごとの`to_le_bytes`で行い、ポインタ再解釈には依存しない(vulkan/geometry/bytes.rsと同じ方針)。
//! シェーダー定数と、照明問い合わせのストレージバッファのレコードが同じこの部品を共有する。

/// 列優先の4x4行列を列の順に詰める。GPU側は`column_major float4x4`として読む。
pub(super) fn 行列を書き込む(バイト列: &mut [u8], 位置: &mut usize, 行列: [[f32; 4]; 4]) {
    for 列 in 行列 {
        vec4を書き込む(バイト列, 位置, 列);
    }
}

pub(crate) fn vec4を書き込む(バイト列: &mut [u8], 位置: &mut usize, 値: [f32; 4]) {
    for 成分 in 値 {
        バイト列[*位置..*位置 + 4].copy_from_slice(&成分.to_le_bytes());
        *位置 += 4;
    }
}

/// GPU側の`uint4`1つを詰める。件数・真偽・判別の種別はfloatの閾値判定を避けてこの経路で渡す。
pub(crate) fn uvec4を書き込む(バイト列: &mut [u8], 位置: &mut usize, 値: [u32; 4]) {
    for 成分 in 値 {
        バイト列[*位置..*位置 + 4].copy_from_slice(&成分.to_le_bytes());
        *位置 += 4;
    }
}

pub(crate) fn ベクトル3をvec4化(ベクトル: [f32; 3], w: f32) -> [f32; 4] {
    [ベクトル[0], ベクトル[1], ベクトル[2], w]
}
