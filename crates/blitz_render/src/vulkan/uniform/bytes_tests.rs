//! フレームユニフォームの各値がシェーダー側のオフセットと一致することの検査。
//! 対応するシェーダー側の宣言は`shaders/scene.slang`の`FrameUniform`であり、
//! 同じUBOを読む`shaders/shadow.slang`・`shaders/cloth_shadow.slang`・`shaders/cloth_draw.slang`・
//! `shaders/sky.slang`・`shaders/particle.slang`も先頭からこの並びを共有する。
//! ここが崩れると値化けとして絵に出るため、オフセットを数値で固定する。

use super::bytes;
use super::content::フレームユニフォーム内容;
use super::sky_content::空ユニフォーム内容;

/// 帯ごとの行列の先頭成分に帯番号+1を置き、どの帯がどのオフセットへ出るかを見分けられるようにする。
fn 内容を作る() -> フレームユニフォーム内容 {
    let 帯行列 = std::array::from_fn(|添字| {
        let mut 行列 = [[0.0_f32; 4]; 4];
        行列[0][0] = f32::from(u8::try_from(添字 + 1).unwrap_or(1));
        行列
    });
    フレームユニフォーム内容 {
        帯ライトビュー射影行列: 帯行列,
        ビュー射影行列: [[10.0, 0.0, 0.0, 0.0], [0.0; 4], [0.0; 4], [0.0; 4]],
        カメラ相対位置: [20.0, 21.0, 22.0],
        方向光方向: [30.0, 31.0, 32.0],
        方向光色: [40.0, 41.0, 42.0],
        方向光強度: 43.0,
        点光源位置: [50.0, 51.0, 52.0],
        点光源色: [60.0, 61.0, 62.0],
        点光源強度: 63.0,
        環境光係数: 70.0,
        ライティング有効: true,
        影を落とす: false,
        帯分割深度: [80.0, 81.0, 82.0],
        帯遷移幅: [90.0, 91.0, 92.0],
        カメラ前方: [100.0, 101.0, 102.0],
        空: 空ユニフォーム内容::空白(),
    }
}

#[test]
fn 共通区画の各値がシェーダーと同じオフセットへ並ぶ() {
    let バイト列 = bytes::バイト列にする(&内容を作る());
    assert_eq!(バイト列.len(), 464 + 272);
    for 添字 in 0..crate::cascade::帯数 {
        assert_eq!(f32を読む(&バイト列, 添字 * 64), f32::from(u8::try_from(添字 + 1).unwrap_or(1)));
    }
    assert_eq!(f32を読む(&バイト列, 256), 10.0);
    assert_eq!(f32を読む(&バイト列, 320), 20.0);
    assert_eq!(f32を読む(&バイト列, 336), 30.0);
    assert_eq!(f32を読む(&バイト列, 352), 40.0);
    assert_eq!(f32を読む(&バイト列, 364), 43.0);
    assert_eq!(f32を読む(&バイト列, 368), 50.0);
    assert_eq!(f32を読む(&バイト列, 384), 60.0);
    assert_eq!(f32を読む(&バイト列, 396), 63.0);
    assert_eq!(f32を読む(&バイト列, 400), 70.0);
    assert_eq!(f32を読む(&バイト列, 404), 1.0);
    assert_eq!(f32を読む(&バイト列, 408), 0.0);
    assert_eq!(f32を読む(&バイト列, 416), 80.0);
    assert_eq!(f32を読む(&バイト列, 432), 90.0);
    assert_eq!(f32を読む(&バイト列, 448), 100.0);
}

/// 空の区画は共通区画の直後から始まる。空パスだけがこの位置以降を読む。
#[test]
fn 空の区画が共通区画の直後から始まる() {
    let mut 内容 = 内容を作る();
    内容.空.放射輝度スケール = [111.0, 112.0, 113.0];
    let バイト列 = bytes::バイト列にする(&内容);
    assert_eq!(f32を読む(&バイト列, 464 + 64 + 9 * 16), 111.0);
}

fn f32を読む(バイト列: &[u8], 位置: usize) -> f32 {
    let 配列 = match バイト列[位置..位置 + 4].try_into() {
        Ok(配列) => 配列,
        Err(_) => panic!("4バイトの切り出しに失敗した"),
    };
    f32::from_le_bytes(配列)
}
