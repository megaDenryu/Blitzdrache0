//! M4固定のライティング定数(判断26)。方向光・点光源・環境光をここへ集約する。
//! 値は開発スレッド「判断24」の確定仕様: 方向光=方向(-0.4,-1,-0.6)正規化・色白・
//! 強度3 / 点光源=位置(2,2,2)・色白・強度10 / 環境光係数0.03。

pub(crate) fn 方向光方向() -> [f32; 3] {
    正規化する([-0.4, -1.0, -0.6])
}

pub(crate) fn 方向光色() -> [f32; 3] {
    [1.0, 1.0, 1.0]
}

pub(crate) fn 方向光強度() -> f32 {
    3.0
}

pub(crate) fn 点光源位置() -> [f32; 3] {
    [2.0, 2.0, 2.0]
}

pub(crate) fn 点光源色() -> [f32; 3] {
    [1.0, 1.0, 1.0]
}

pub(crate) fn 点光源強度() -> f32 {
    10.0
}

pub(crate) fn 環境光係数() -> f32 {
    0.03
}

fn 正規化する(ベクトル: [f32; 3]) -> [f32; 3] {
    let 長さ = (ベクトル[0] * ベクトル[0] + ベクトル[1] * ベクトル[1] + ベクトル[2] * ベクトル[2]).sqrt();
    [ベクトル[0] / 長さ, ベクトル[1] / 長さ, ベクトル[2] / 長さ]
}
