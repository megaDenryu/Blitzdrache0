//! フレームユニフォームへ書き込む内容。std140/HLSL cbufferのどちらでも
//! 16バイト境界を跨がないよう、行列以外は全フィールドをvec4単位にそろえて
//! GPU側(shaders/scene.slangのFrameUniform)と1対1に対応させる(判断24)。
//!
//! 注意: フィールド順序はshaders/scene.slangのFrameUniform構造体の宣言順と
//! 完全に一致させること。ここを崩すと`bytes::バイト列にする`のオフセット計算が
//! シェーダー側とずれ、値化けとして現れる。

use crate::cascade::{帯境界数, 帯数};

use super::sky_content::空ユニフォーム内容;

pub(crate) struct フレームユニフォーム内容 {
    /// 判断35・36: シャドウパスの頂点シェーダーが読む唯一のフィールドのため先頭に置く。
    /// シャドウパスは binding3 を「先頭に帯ごとの光源ビュー射影行列の配列だけを持つ構造体」として
    /// 解釈するため、この配列がバイト列の先頭(オフセット0)にあることが前提条件になる
    /// (`bytes::バイト列にする`のコメント参照)。
    pub(crate) 帯ライトビュー射影行列: [[[f32; 4]; 4]; 帯数],
    pub(crate) ビュー射影行列: [[f32; 4]; 4],
    pub(crate) カメラ相対位置: [f32; 3],
    pub(crate) 方向光方向: [f32; 3],
    pub(crate) 方向光色: [f32; 3],
    pub(crate) 方向光強度: f32,
    pub(crate) 点光源位置: [f32; 3],
    pub(crate) 点光源色: [f32; 3],
    pub(crate) 点光源強度: f32,
    pub(crate) 環境光係数: f32,
    pub(crate) ライティング有効: bool,
    /// 方向光が影を落とすか。falseのときシーンのフラグメントはシャドウマップを1度も引かない。
    pub(crate) 影を落とす: bool,
    /// 帯の境界のビュー空間深度。シーンのフラグメントがこの値で引く帯を選ぶ。
    pub(crate) 帯分割深度: [f32; 帯境界数],
    /// 帯の境界の手前に置く遷移帯の幅。この幅の中で2つの帯を混ぜる。
    pub(crate) 帯遷移幅: [f32; 帯境界数],
    /// カメラの前方向(カメラ相対フレームの単位ベクトル)。ビュー空間深度を内積で求めるために渡す。
    pub(crate) カメラ前方: [f32; 3],
    /// 空パスだけが読む後半の区画。空段階が無いフレーム構成では`空白`を書く。
    pub(crate) 空: 空ユニフォーム内容,
}
