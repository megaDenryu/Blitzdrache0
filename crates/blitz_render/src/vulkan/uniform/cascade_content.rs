//! 多段影定数へ書き込む内容。シーンの影評価とシャドウ記録パスが同じ1本を読む。
//! std140/HLSL cbufferのどちらでも16バイト境界を跨がないよう、行列以外は全フィールドをvec4単位にそろえて
//! GPU側(shaders/cascade_shadow_uniform.slangのCascadeShadowUniform)と1対1に対応させる(判断24)。
//!
//! 注意: フィールド順序はshaders/cascade_shadow_uniform.slangの宣言順と完全に一致させること。
//! ここを崩すと`cascade_bytes::バイト列にする`の開始位置がシェーダー側とずれ、値化けとして現れる。

use crate::cascade::{距離区分の境界数, 距離区分数};

pub(crate) struct 多段影定数内容 {
    pub(crate) 距離区分のライトビュー射影行列: [[[f32; 4]; 4]; 距離区分数],
    /// 距離区分の境界のビュー空間深度。シーンの画素段がこの値で参照する距離区分を選ぶ。
    pub(crate) 距離区分の分割深度: [f32; 距離区分の境界数],
    /// 距離区分の境界の手前に置く遷移域の幅。この幅の中で2つの距離区分を混ぜる。
    pub(crate) 距離区分の遷移幅: [f32; 距離区分の境界数],
    /// 方向光が影を落とすか。falseのときシーンの画素段はシャドウマップを1度も参照しない。
    pub(crate) 影を落とす: bool,
    /// 距離区分の可視化を行うか。
    pub(crate) 距離区分を可視化する: bool,
    /// シャドウマップの1テクセルが占める正規化座標の幅。PCFの標本位置の刻みに使う。
    pub(crate) シャドウマップのテクセル尺度: f32,
}
