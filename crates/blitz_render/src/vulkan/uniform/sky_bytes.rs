//! 空パス定数をバイト列へ組み立てる工程。受け取るのは定数内容、返すのは
//! shaders/sky_pass_uniform.slangのSkyPassUniformと同じ並びのバイト列である。
//!
//! 注意: 並びはシェーダー側の宣言順と完全に一致させること。ここを崩すと値化けとして現れる。

use super::sky_content::空パス定数内容;
use super::write_bytes::{vec4を書き込む, ベクトル3をvec4化, 行列を書き込む};

/// バイト長: 行列1つ(64) + vec4単位3個(48) = 112。
pub(crate) const バイト長: usize = 64 + 48;

pub(super) fn バイト列にする(内容: &空パス定数内容) -> [u8; バイト長] {
    let mut バイト列 = [0u8; バイト長];
    let mut 位置 = 0usize;

    行列を書き込む(&mut バイト列, &mut 位置, 内容.逆ビュー射影行列);
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.夜空放射輝度, 内容.太陽円盤の余弦角半径));
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.太陽方向, 内容.観測高度));
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(内容.太陽円盤放射輝度, 内容.太陽放射照度));
    バイト列
}
