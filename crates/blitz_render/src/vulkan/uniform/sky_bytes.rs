//! 空の区画をバイト列へ組み立てる工程。担当するのは「空シェーダー定数内容と書き込み位置を受け取り、
//! shaders/sky_frame.slangのSkyFrameUniformの後半と同じ並びで詰める」ことである。
//!
//! 注意: 並びはシェーダー側の宣言順と完全に一致させること。ここを崩すと値化けとして現れる。

use super::sky_content::空シェーダー定数内容;

/// 空の区画のバイト長: 行列1つ(64) + vec4単位3個(48) = 112。
pub(super) const 空区画バイト長: usize = 112;
use super::bytes::{vec4を書き込む, ベクトル3をvec4化, 行列を書き込む};

pub(super) fn 書き込む(バイト列: &mut [u8], 位置: &mut usize, 内容: &空シェーダー定数内容) {
    行列を書き込む(バイト列, 位置, 内容.逆ビュー射影行列);
    vec4を書き込む(バイト列, 位置, ベクトル3をvec4化(内容.夜空放射輝度, 内容.太陽円盤の余弦角半径));
    vec4を書き込む(バイト列, 位置, ベクトル3をvec4化(内容.太陽方向, 内容.観測高度));
    vec4を書き込む(バイト列, 位置, ベクトル3をvec4化(内容.太陽円盤放射輝度, 内容.太陽放射照度));
}
