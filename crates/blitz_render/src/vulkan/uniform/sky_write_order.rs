//! 空パス定数をこのフレームで書くかどうかの判断。担当するのは「空段階の有無とフレーム描画入力の空の有無を
//! 受け取り、書く先の入力を持つ指示か、書かない指示を返す」ことである。GPUにも行列にも触れない。
//!
//! 不変条件: 空パス資源の有無とフレーム描画入力の空の有無は常に一致する。不一致は型付きエラーにする。
//! 空段階を持たないフレーム構成で空パス定数のバッファを書かないのは、そのフレームで誰も読まない値の
//! ホスト可視メモリへの書き込みを毎フレーム積まないためである
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「分離の形」)。

use crate::error::{レンダラーエラー, 空エラー};
use crate::frame_input::空入力;

pub(crate) enum 空パス定数の書込指示<'a> {
    書き込む(&'a 空入力),
    書き込まない,
}

pub(crate) fn 空パス定数の書込指示を決める<'a>(
    空を描くか: bool,
    空入力: Option<&'a 空入力>,
) -> Result<空パス定数の書込指示<'a>, レンダラーエラー> {
    match (空を描くか, 空入力) {
        (true, Some(入力)) => Ok(空パス定数の書込指示::書き込む(入力)),
        (false, None) => Ok(空パス定数の書込指示::書き込まない),
        (true, None) => Err(空エラー::入力不一致("空段階があるフレーム構成なのに空入力が未指定".to_string()).into()),
        (false, Some(_)) => Err(空エラー::入力不一致("空段階の無いフレーム構成に空入力が指定された".to_string()).into()),
    }
}
