//! 大気のベイク済み画像生成パス1フレームぶんの入力の記録。フレーム構成に空段階があり、かつそのフレームでベイク済み画像を焼くときだけ`Some`で渡す。
//!
//! 画像そのものでなくハンドルを運ばないのは、グラフへの登録が`graph_build`側の担当だからである。
//! ここが運ぶのは束縛先(パイプライン・レイアウト・ディスクリプタセット)と、ディスパッチするワークグループ数、
//! それにディスパッチ前へ押し込む定数だけである。押し込み定数のバイト並びは`push_constants`、
//! ワークグループ数の求め方は`workgroup_count`が持つ。

mod push_constants;
mod workgroup_count;

use ash::vk;

pub(crate) use push_constants::生成の押し込み定数;
pub(super) use workgroup_count::ワークグループ数を求める;

use super::大気のベイク済み画像の形;

/// 1本のコンピュートパスが束縛する資源とディスパッチの大きさ。
pub(crate) struct 大気のベイク済み画像の生成入力 {
    pub(crate) pipeline: vk::Pipeline,
    pub(crate) layout: vk::PipelineLayout,
    pub(crate) ディスクリプタセット: vk::DescriptorSet,
    pub(crate) ワークグループ数: [u32; 3],
    pub(crate) 押し込み定数: 生成の押し込み定数,
}

/// ベイク済み画像1枚の画像としての姿。グラフへ資源を登録するのに要る3つだけを持つ。
pub(crate) struct 大気のベイク済み画像の画像入力 {
    pub(crate) 画像: vk::Image,
    pub(crate) ビュー: vk::ImageView,
    pub(crate) 形: 大気のベイク済み画像の形,
}

/// そのフレームで焼く条件依存の3枚の組。取りうる組み合わせを3つに限る。
///
/// 透過率と多重散乱を単独で焼く腕を持たないのは、スカイビューの内容が2枚の両方に依存し、大気が変わった以上
/// スカイビューも必ず焼き直さねばならないためである。逆にスカイビューだけを焼く腕が要るのは、
/// 大気が変わらないまま太陽や観測点が動くフレームがあるためである。
///
/// 空中遠近をこの組へ入れないのは、焼くかどうかを決めるものが別だからである。3枚は観測条件だけで決まるのに対し、
/// 空中遠近は空段階が空中遠近合成を持つことも条件に持ち、依存する先も透過率と多重散乱の2枚だけで
/// スカイビューを含まない。1つの列挙へ混ぜると、合成の有無による条件と観測条件による有無が同じ列挙の中で絡む。
///
/// 腕の大きさの差(`全部`が312バイト、`スカイビューだけ`が104バイト)を許すのは、この値がフレームごとに
/// 1つだけスタックへ載り、配列にもコレクションにも入らないためである。差の出どころは空中遠近の押し込み定数の
/// 4組16実数であり、3枚の平面のベイク済み画像はその腕を持ちえないが型を共有している。clippyが勧める`Box`は、
/// 200バイトほどのスタックを節約する代わりに毎フレームのヒープ確保を1回増やすため採らない
/// (参照: `_doc/設計/性能アーキテクチャ方針.md`「日常の性能規律」)。
#[allow(clippy::large_enum_variant)]
pub(crate) enum 生成する組 {
    /// どのベイク済み画像も前の結果を使う。生成パスを1本も積まない。
    何も焼かない,
    /// 大気は変わらず、太陽か観測点が動いた。
    スカイビューだけ {
        スカイビュー: 大気のベイク済み画像の生成入力
    },
    /// 大気が変わった、またはまだ1度も焼いていない。
    全部 {
        透過率: 大気のベイク済み画像の生成入力,
        多重散乱: 大気のベイク済み画像の生成入力,
        スカイビュー: 大気のベイク済み画像の生成入力,
    },
}

/// そのフレームに積む大気のベイク済み画像の生成パス一式と、パスが触れる画像。
///
/// 空中遠近が`None`になるのは2つの場合である。`--no-aerial-composite`で合成を切った構成のとき
/// (ボリュームを誰も参照しないため焼かない)と、合成がある構成でカメラも太陽も大気も動かなかったときである。
pub(crate) struct 大気のベイク済み画像の描画入力 {
    pub(crate) 焼く組: 生成する組,
    pub(crate) 空中遠近: Option<大気のベイク済み画像の生成入力>,
    pub(crate) 透過率画像: 大気のベイク済み画像の画像入力,
    pub(crate) 多重散乱画像: 大気のベイク済み画像の画像入力,
    pub(crate) スカイビュー画像: 大気のベイク済み画像の画像入力,
    pub(crate) 空中遠近画像: 大気のベイク済み画像の画像入力,
}
