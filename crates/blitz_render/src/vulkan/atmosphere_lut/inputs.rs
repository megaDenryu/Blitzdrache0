//! 大気LUT生成パス1フレームぶんの入力。フレーム構成に空段階があり、かつそのフレームでLUTを焼くときだけ`Some`で渡す。
//!
//! 画像そのものでなくハンドルを運ばないのは、グラフへの登録が`graph_build`側の担当だからである。
//! ここが運ぶのは束縛先(パイプライン・レイアウト・ディスクリプタセット)と、ディスパッチするワークグループ数、
//! それにディスパッチ前へ押し込む定数だけである。

use ash::vk;

/// ディスパッチ前に押し込む定数。透過率と多重散乱は媒体のユニフォームだけで内容が決まるため持たない。
/// スカイビューだけが観測点と太陽の向きを持つのは、媒体が変わらないまま太陽だけが動くフレームでも
/// この2つは書き換わるためである。ユニフォームへ載せると書き換えの時機が媒体と別になり、スロットごとの
/// 書き込みの規律を2つ持つことになる。
#[derive(Debug, Clone, Copy)]
pub(crate) enum 生成の押し込み定数 {
    無し,
    スカイビュー条件 { 観測半径: f32, 太陽天頂余弦: f32 },
}

/// 1本のコンピュートパスが束縛する資源とディスパッチの大きさ。
pub(crate) struct 大気LUT生成入力 {
    pub(crate) pipeline: vk::Pipeline,
    pub(crate) layout: vk::PipelineLayout,
    pub(crate) ディスクリプタセット: vk::DescriptorSet,
    pub(crate) ワークグループ数: [u32; 2],
    pub(crate) 押し込み定数: 生成の押し込み定数,
}

/// LUT1枚の画像としての姿。グラフへ資源を登録するのに要る3つだけを持つ。
pub(crate) struct 大気LUT画像入力 {
    pub(crate) 画像: vk::Image,
    pub(crate) ビュー: vk::ImageView,
    pub(crate) 寸法: vk::Extent2D,
}

/// そのフレームで焼くLUTの組。取りうる組み合わせを3つに限る。
///
/// 透過率と多重散乱を単独で焼く腕を持たないのは、スカイビューの内容が2枚の両方に依存し、
/// 大気が変わった以上スカイビューも必ず焼き直さねばならないためである。逆にスカイビューだけを焼く腕が要るのは、
/// 大気が変わらないまま太陽や観測点が動くフレームがあるためである。
pub(crate) enum 生成する組 {
    /// どのLUTも前の結果を使う。生成パスを1本も積まない。
    何も焼かない,
    /// 大気は変わらず、太陽か観測点が動いた。
    スカイビューだけ { スカイビュー: 大気LUT生成入力 },
    /// 大気が変わった、またはまだ1度も焼いていない。
    全部 {
        透過率: 大気LUT生成入力,
        多重散乱: 大気LUT生成入力,
        スカイビュー: 大気LUT生成入力,
    },
}

/// そのフレームに積む大気LUTの生成パス一式と、パスが触れる画像。
pub(crate) struct 大気LUT描画入力 {
    pub(crate) 焼く組: 生成する組,
    pub(crate) 透過率画像: 大気LUT画像入力,
    pub(crate) 多重散乱画像: 大気LUT画像入力,
    pub(crate) スカイビュー画像: 大気LUT画像入力,
}

/// 1ワークグループが受け持つテクセルの一辺。生成シェーダーの`numthreads`と一致させる。
const ワークグループの一辺: u32 = 8;

/// LUTの寸法から、全テクセルを覆うのに要るワークグループの数を求める。端数のワークグループは
/// 書き込み先の寸法を超えたスレッドを自分で捨てるため、切り上げてよい。
pub(super) fn ワークグループ数を求める(幅: u32, 高さ: u32) -> [u32; 2] {
    [幅.div_ceil(ワークグループの一辺), 高さ.div_ceil(ワークグループの一辺)]
}
