//! そのフレームの大気LUT生成パスが束縛する資源を組む局面。呼ばれるのは毎フレーム1回であり、生成と破棄の局面とは
//! 呼び出し頻度が桁で違う。触れるのは解像度と束縛一式と画像の3つだけで、どのハンドルも作らず参照するだけである。
//!
//! 焼く組の腕を指示から決めるのは、レンダラーが鍵そのものを受け取れないためである(参照: `atmosphere_lut_input`)。

use super::{
    inputs::ワークグループ数を求める, 大気LUT一式, 大気LUT描画入力, 大気LUT生成入力, 生成する組, 生成の押し込み定数
};
use crate::atmosphere::{スカイビュー観測条件, 大気散乱媒体};
use crate::atmosphere_lut_input::大気LUT生成指示;
use crate::vulkan::sync::フレームスロット添字;

impl 大気LUT一式 {
    /// そのフレームの生成パスが束縛する資源。スカイビューの条件は押し込み定数として運ぶため、
    /// 観測点と太陽の向きが変わっただけのフレームではユニフォームへ1バイトも書かない。
    pub(crate) fn 描画入力を作る(
        &self,
        フレーム添字: フレームスロット添字,
        媒体: &大気散乱媒体,
        条件: スカイビュー観測条件,
        指示: 大気LUT生成指示,
    ) -> 大気LUT描画入力 {
        大気LUT描画入力 {
            焼く組: self.焼く組を作る(フレーム添字, 媒体, 条件, 指示),
            透過率画像: self.基盤.透過率.画像入力を作る(),
            多重散乱画像: self.基盤.多重散乱.画像入力を作る(),
            スカイビュー画像: self.基盤.スカイビュー.画像入力を作る(),
        }
    }

    fn 焼く組を作る(
        &self,
        フレーム添字: フレームスロット添字,
        媒体: &大気散乱媒体,
        条件: スカイビュー観測条件,
        指示: 大気LUT生成指示,
    ) -> 生成する組 {
        match 指示 {
            大気LUT生成指示::前の結果を使う => 生成する組::何も焼かない,
            大気LUT生成指示::スカイビューだけ焼き直す => 生成する組::スカイビューだけ {
                スカイビュー: self.スカイビュー入力(フレーム添字, 媒体, 条件),
            },
            大気LUT生成指示::全部焼き直す => 生成する組::全部 {
                透過率: self.透過率入力(フレーム添字),
                多重散乱: self.多重散乱入力(フレーム添字),
                スカイビュー: self.スカイビュー入力(フレーム添字, 媒体, 条件),
            },
        }
    }

    fn 透過率入力(&self, フレーム添字: フレームスロット添字) -> 大気LUT生成入力 {
        大気LUT生成入力 {
            pipeline: self.束縛.透過率パイプライン.handle,
            layout: self.束縛.透過率パイプライン.layout,
            ディスクリプタセット: self.束縛.透過率セット(フレーム添字),
            ワークグループ数: ワークグループ数を求める(self.解像度.透過率の幅(), self.解像度.透過率の高さ()),
            押し込み定数: 生成の押し込み定数::無し,
        }
    }

    fn 多重散乱入力(&self, フレーム添字: フレームスロット添字) -> 大気LUT生成入力 {
        let 一辺 = self.解像度.多重散乱の一辺();
        大気LUT生成入力 {
            pipeline: self.束縛.多重散乱パイプライン.handle,
            layout: self.束縛.多重散乱パイプライン.layout,
            ディスクリプタセット: self.束縛.多重散乱セット(フレーム添字),
            ワークグループ数: ワークグループ数を求める(一辺, 一辺),
            押し込み定数: 生成の押し込み定数::無し,
        }
    }

    fn スカイビュー入力(
        &self, フレーム添字: フレームスロット添字, 媒体: &大気散乱媒体, 条件: スカイビュー観測条件
    ) -> 大気LUT生成入力 {
        大気LUT生成入力 {
            pipeline: self.束縛.スカイビューパイプライン.handle,
            layout: self.束縛.スカイビューパイプライン.layout,
            ディスクリプタセット: self.束縛.スカイビューセット(フレーム添字),
            ワークグループ数: ワークグループ数を求める(self.解像度.スカイビューの幅(), self.解像度.スカイビューの高さ()),
            押し込み定数: 生成の押し込み定数::スカイビュー条件 {
                観測半径: 条件.観測半径(媒体.消散()).値(),
                太陽天頂余弦: 条件.太陽天頂余弦().値(),
            },
        }
    }
}
