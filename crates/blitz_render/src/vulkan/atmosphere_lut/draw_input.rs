//! そのフレームに積む生成パスの集合を、指示と空パスの方式から決める局面。呼ばれるのは毎フレーム1回であり、
//! 生成と破棄の局面とは呼び出し頻度が桁で違う。決めるのは在るか無いかだけで、1本ぶんの束縛は`pass_binding`が組む。
//!
//! 焼く組を指示から決めるのは、レンダラーが鍵そのものを受け取れないためである(参照: `atmosphere_lut_input`)。
//! 空中遠近を焼くかどうかは、指示のほかに空段階が空中遠近合成を持つかにも依る。`--no-aerial-composite`で
//! 合成を切った構成ではボリュームを誰も引かないため焼かない。

mod pass_binding;

use super::{大気LUT一式, 大気LUT描画入力, 大気LUT生成入力, 生成する組};
use crate::atmosphere::{スカイビュー観測条件, 大気散乱媒体, 空中遠近観測条件};
use crate::atmosphere_lut_input::大気LUT生成指示;
use crate::vulkan::sync::フレームスロット添字;

/// 1フレームぶんの描画入力を組むのに要る条件。引数の列が伸び続けるのを避けて1つに束ねる。
pub(crate) struct 描画入力の材料<'a> {
    pub(crate) フレーム添字: フレームスロット添字,
    pub(crate) 媒体: &'a 大気散乱媒体,
    pub(crate) スカイビュー条件: スカイビュー観測条件,
    pub(crate) 空中遠近条件: 空中遠近観測条件,
    pub(crate) 指示: 大気LUT生成指示,
    /// 空段階が空中遠近合成を持つか。`--no-aerial-composite`で合成を切った構成では空中遠近を1度も焼かない。
    pub(crate) 空中遠近を引くか: bool,
}

impl 大気LUT一式 {
    /// そのフレームの生成パスが束縛する資源。スカイビューと空中遠近の条件は押し込み定数として運ぶため、
    /// 観測点や太陽やカメラが変わっただけのフレームではユニフォームへ1バイトも書かない。
    pub(crate) fn 描画入力を作る(&self, 材料: &描画入力の材料<'_>) -> 大気LUT描画入力 {
        大気LUT描画入力 {
            焼く組: self.焼く組を作る(材料),
            空中遠近: self.空中遠近を焼くなら組む(材料),
            透過率画像: self.基盤.透過率.画像入力を作る(),
            多重散乱画像: self.基盤.多重散乱.画像入力を作る(),
            スカイビュー画像: self.基盤.スカイビュー.画像入力を作る(),
            空中遠近画像: self.基盤.空中遠近.画像入力を作る(),
        }
    }

    fn 焼く組を作る(&self, 材料: &描画入力の材料<'_>) -> 生成する組 {
        match 材料.指示 {
            大気LUT生成指示::前の結果を使う | 大気LUT生成指示::空中遠近だけ焼き直す => {
                生成する組::何も焼かない
            }
            大気LUT生成指示::スカイビューと空中遠近を焼き直す => 生成する組::スカイビューだけ {
                スカイビュー: self.スカイビュー入力(材料),
            },
            大気LUT生成指示::全部焼き直す => 生成する組::全部 {
                透過率: self.透過率入力(材料.フレーム添字),
                多重散乱: self.多重散乱入力(材料.フレーム添字),
                スカイビュー: self.スカイビュー入力(材料),
            },
        }
    }

    /// 空中遠近を焼くのは、空段階が空中遠近合成を持ち、かつ指示が「前の結果を使う」以外のフレームである。
    fn 空中遠近を焼くなら組む(&self, 材料: &描画入力の材料<'_>) -> Option<大気LUT生成入力> {
        if !材料.空中遠近を引くか || 材料.指示 == 大気LUT生成指示::前の結果を使う {
            return None;
        }
        Some(self.空中遠近入力(材料))
    }
}
