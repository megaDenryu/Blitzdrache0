//! ウィンドウを持たないGPUで大気LUTを焼き、中身をホストへ読み戻す工程。
//! 受け取るのは媒体・解像度・シェーダー、返すのは2枚のLUTの生の4成分である。
//!
//! 値オブジェクトでなく生の4成分で返すのは、検査が非有限値や負の値を観測できなければならないためである。
//! 検証済みの型で返すと、まさに検査したい壊れた値が構築の時点で弾かれてしまう。
//!
//! 本番のフレーム記録と同じパス宣言(`pass`)を同じレンダーグラフへ積むため、バリアの導出も本番と同じ経路を通る。

mod record;

use crate::atmosphere::{大気LUT解像度, 大気散乱媒体};
use crate::error::レンダラーエラー;
use crate::shader_bundle::大気LUTシェーダー一式;
use crate::vulkan::headless::ヘッドレスGPU環境;
use crate::vulkan::sync::フレームスロット添字;

use super::readback_buffer::LUT読み戻しバッファ;
use super::大気LUT一式;

/// 2枚のLUTを焼いて読み戻した結果。並びは行優先であり、CPU正本が焼く並びと一致する。
pub(crate) struct 大気LUT読み戻し {
    pub(crate) 透過率: Vec<[f32; 4]>,
    pub(crate) 多重散乱: Vec<[f32; 4]>,
}

pub(crate) fn 大気lutをgpuで焼いて読み戻す(
    媒体: &大気散乱媒体,
    解像度: 大気LUT解像度,
    シェーダー: &大気LUTシェーダー一式,
) -> Result<大気LUT読み戻し, レンダラーエラー> {
    let 環境 = ヘッドレスGPU環境::生成する()?;
    let 結果 = 環境で焼く(&環境, 媒体, 解像度, シェーダー);
    環境.破棄する();
    結果
}

fn 環境で焼く(
    環境: &ヘッドレスGPU環境,
    媒体: &大気散乱媒体,
    解像度: 大気LUT解像度,
    シェーダー: &大気LUTシェーダー一式,
) -> Result<大気LUT読み戻し, レンダラーエラー> {
    let device = 環境.device();
    let メモリプロパティ = 環境.メモリプロパティを取得する();
    let 一式 = 大気LUT一式::生成する(device, &メモリプロパティ, 解像度, シェーダー)?;
    let 結果 = 一式で焼く(環境, &一式, 媒体, 解像度, &メモリプロパティ);
    一式.破棄する(device);
    結果
}

fn 一式で焼く(
    環境: &ヘッドレスGPU環境,
    一式: &大気LUT一式,
    媒体: &大気散乱媒体,
    解像度: 大気LUT解像度,
    メモリプロパティ: &ash::vk::PhysicalDeviceMemoryProperties,
) -> Result<大気LUT読み戻し, レンダラーエラー> {
    let device = 環境.device();
    let スロット = フレームスロット添字::先頭();
    一式.媒体を書き込む(device, スロット, 媒体)?;
    let 透過率受け = LUT読み戻しバッファ::生成する(device, メモリプロパティ, 解像度.透過率のテクセル数())?;
    let 結果 = 受け皿を揃えて焼く(環境, 一式, 解像度, メモリプロパティ, &透過率受け);
    透過率受け.破棄する(device);
    結果
}

fn 受け皿を揃えて焼く(
    環境: &ヘッドレスGPU環境,
    一式: &大気LUT一式,
    解像度: 大気LUT解像度,
    メモリプロパティ: &ash::vk::PhysicalDeviceMemoryProperties,
    透過率受け: &LUT読み戻しバッファ,
) -> Result<大気LUT読み戻し, レンダラーエラー> {
    let device = 環境.device();
    let 多重散乱受け = LUT読み戻しバッファ::生成する(device, メモリプロパティ, 解像度.多重散乱のテクセル数())?;
    let 結果 = record::焼いて読み戻す(環境, 一式, 透過率受け, &多重散乱受け);
    多重散乱受け.破棄する(device);
    結果
}
