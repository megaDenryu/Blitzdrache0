//! 大気のベイク済み画像のうち、GPUメモリを占める資源(5枚のベイク済み画像と媒体のシェーダー定数)の所有者。
//! 触れるのはこの6つだけであり、ディスクリプタもパイプラインも持たない。生成の途中で失敗したら
//! それまでに確保したメモリをその場で解放する。画像を順に確保する巻き戻しは`images`が持つ。
//!
//! 遠方環境用スカイビューを連続なスカイビューと同じ形で別に持つのは、遠方環境が代表天頂余弦で焼いた表だけを
//! 読むためである。連続な表を読むと、同じ区間の中のどのフレームで焼いたかで遠方環境の内容が変わり、
//! 「同じ鍵なら同じ画像」が壊れる(参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」)。

mod images;

use ash::vk;

use super::{image, medium_uniform, 大気のベイク済み画像の形};
use crate::atmosphere::{大気のベイク済み画像の解像度, 大気散乱媒体};
use crate::error::レンダラーエラー;
use crate::vulkan::allocator::GPU資源の確保係;
use crate::vulkan::sync::{フレームスロット添字, 進行中フレーム数};
use crate::vulkan::tracked_device::GPUデバイス;

pub(super) struct 大気のベイク済み画像の基盤資源 {
    pub(super) 透過率: image::大気のベイク済み画像,
    pub(super) 多重散乱: image::大気のベイク済み画像,
    pub(super) スカイビュー: image::大気のベイク済み画像,
    /// 遠方環境の生成だけが読む、代表天頂余弦で焼いたスカイビュー。空背景と空中遠近は上の連続な1枚を読む。
    pub(super) 遠方環境用スカイビュー: image::大気のベイク済み画像,
    pub(super) 空中遠近: image::大気のベイク済み画像,
    媒体シェーダー定数: medium_uniform::媒体シェーダー定数一式,
}

impl 大気のベイク済み画像の基盤資源 {
    pub(super) fn 生成する(
        確保係: &GPU資源の確保係<'_>, 解像度: 大気のベイク済み画像の解像度
    ) -> Result<Self, レンダラーエラー> {
        let device = 確保係.論理デバイス();
        let 多重散乱の一辺 = 解像度.多重散乱の一辺();
        let スカイビューの形 = 平面(解像度.スカイビューの幅(), 解像度.スカイビューの高さ());
        let 形一覧 = [
            平面(解像度.透過率の幅(), 解像度.透過率の高さ()),
            平面(多重散乱の一辺, 多重散乱の一辺),
            スカイビューの形,
            スカイビューの形,
            大気のベイク済み画像の形::立体 {
                一辺: 解像度.空中遠近の一辺(),
            },
        ];
        let [透過率, 多重散乱, スカイビュー, 遠方環境用スカイビュー, 空中遠近] = images::順に作る(確保係, 形一覧)?;
        match medium_uniform::媒体シェーダー定数一式::生成する(確保係) {
            Ok(媒体シェーダー定数) => Ok(Self {
                透過率,
                多重散乱,
                スカイビュー,
                遠方環境用スカイビュー,
                空中遠近,
                媒体シェーダー定数,
            }),
            Err(誤り) => {
                空中遠近.破棄する(device);
                遠方環境用スカイビュー.破棄する(device);
                スカイビュー.破棄する(device);
                多重散乱.破棄する(device);
                透過率.破棄する(device);
                Err(誤り)
            }
        }
    }

    /// ディスクリプタが結ぶシェーダー定数のバッファをスロット順に並べたもの。
    pub(super) fn シェーダー定数一覧(&self) -> [vk::Buffer; 進行中フレーム数] {
        let mut 一覧 = [vk::Buffer::null(); 進行中フレーム数];
        for 添字 in フレームスロット添字::全スロット() {
            一覧[添字.配列添字()] = self.媒体シェーダー定数.フレームスロットのバッファ(添字);
        }
        一覧
    }

    /// 前提: 呼び出し元はこのスロットのフェンス待機を済ませている(`draw_execute/prepare.rs`)。
    pub(super) fn 媒体を書き込む(
        &self,
        device: &ash::Device,
        フレーム添字: フレームスロット添字,
        媒体: &大気散乱媒体,
    ) -> Result<(), レンダラーエラー> {
        self.媒体シェーダー定数.書き込む(device, フレーム添字, 媒体)
    }

    pub(super) fn 破棄する(&self, device: &GPUデバイス) {
        self.媒体シェーダー定数.破棄する(device);
        self.空中遠近.破棄する(device);
        self.遠方環境用スカイビュー.破棄する(device);
        self.スカイビュー.破棄する(device);
        self.多重散乱.破棄する(device);
        self.透過率.破棄する(device);
    }
}

fn 平面(幅: u32, 高さ: u32) -> 大気のベイク済み画像の形 {
    大気のベイク済み画像の形::平面 { 幅, 高さ }
}
