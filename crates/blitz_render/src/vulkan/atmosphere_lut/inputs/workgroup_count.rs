//! 1計算の班が受け持つテクセルの範囲と、ベイク済み画像の形から要る計算の班数を求める工程。
//! 受け取るのはベイク済み画像1枚の形、返すのは計算の発行の3成分である。
//!
//! 一辺の値をここが単独で持つのは、シェーダー側の`numthreads`と同じ値でなければならないためである。
//! 食い違うと端のテクセルが焼かれないか二重に焼かれる。

use crate::vulkan::atmosphere_lut::大気のベイク済み画像の形;

/// 1計算の班が受け持つテクセルの一辺。平面のベイク済み画像は8、立体のボリュームは4である。
/// 立体を4に下げるのは、8の3乗が512スレッドで多くの機材の1計算の班の上限1024に近く、
/// レジスタの使用量で占有率が落ちるためである。4の3乗の64スレッドはワープ2つぶんに収まる。
const 平面の計算の班の一辺: u32 = 8;
const 立体の計算の班の一辺: u32 = 4;

/// ベイク済み画像の形から、全テクセルを覆うのに要る計算の班の数を求める。端数の計算の班は
/// 書き込み先の寸法を超えたスレッドを自分で捨てるため、切り上げてよい。
pub(in crate::vulkan::atmosphere_lut) fn 計算の班数を求める(形: 大気のベイク済み画像の形) -> [u32; 3] {
    let 範囲 = 形.範囲();
    let 一辺 = match 形 {
        大気のベイク済み画像の形::平面 { .. } => 平面の計算の班の一辺,
        大気のベイク済み画像の形::立体 { .. } => 立体の計算の班の一辺,
    };
    [範囲.width.div_ceil(一辺), 範囲.height.div_ceil(一辺), 範囲.depth.div_ceil(一辺)]
}
