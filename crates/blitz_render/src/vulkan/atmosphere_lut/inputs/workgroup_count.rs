//! 1ワークグループが受け持つテクセルの範囲と、LUTの形から要るワークグループ数を求める工程。
//! 受け取るのはLUT1枚の形、返すのはディスパッチの3成分である。
//!
//! 一辺の値をここが単独で持つのは、シェーダー側の`numthreads`と同じ値でなければならないためである。
//! 食い違うと端のテクセルが焼かれないか二重に焼かれる。

use crate::vulkan::atmosphere_lut::大気LUTの形;

/// 1ワークグループが受け持つテクセルの一辺。平面のLUTは8、立体のボリュームは4である。
/// 立体を4に下げるのは、8の3乗が512スレッドで多くの機材の1ワークグループの上限1024に近く、
/// レジスタの使用量で占有率が落ちるためである。4の3乗の64スレッドはワープ2つぶんに収まる。
const 平面のワークグループの一辺: u32 = 8;
const 立体のワークグループの一辺: u32 = 4;

/// LUTの形から、全テクセルを覆うのに要るワークグループの数を求める。端数のワークグループは
/// 書き込み先の寸法を超えたスレッドを自分で捨てるため、切り上げてよい。
pub(in crate::vulkan::atmosphere_lut) fn ワークグループ数を求める(形: 大気LUTの形) -> [u32; 3] {
    let 範囲 = 形.範囲();
    let 一辺 = match 形 {
        大気LUTの形::平面 { .. } => 平面のワークグループの一辺,
        大気LUTの形::立体 { .. } => 立体のワークグループの一辺,
    };
    [範囲.width.div_ceil(一辺), 範囲.height.div_ceil(一辺), 範囲.depth.div_ceil(一辺)]
}
