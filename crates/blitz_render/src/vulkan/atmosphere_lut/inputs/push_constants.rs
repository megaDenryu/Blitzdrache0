//! 生成パスがディスパッチ前に押し込む定数の枝と、そのバイト並び。
//! 受け取るのは条件の値そのもの、返すのはシェーダー側の宣言と同じ並びのバイト列である。
//!
//! バイト並びをここが単独で持つのは、これがCPUとシェーダーの即時定数の構造体の間の唯一の契約だからである。
//! 並びが食い違えば型検査は通ったまま値が入れ替わるため、詰め方を1箇所に閉じて詰める側と読む側を1対1に保つ。

/// ディスパッチ前に押し込む定数。透過率と多重散乱は媒体のシェーダー定数だけで内容が決まるため持たない。
/// スカイビューと空中遠近が持つのは、媒体が変わらないまま太陽やカメラだけが動くフレームでも
/// これらが書き換わるためである。シェーダー定数へ載せると書き換えの時機が媒体と別になり、スロットごとの
/// 書き込みの規律を2つ持つことになる。
#[derive(Debug, Clone, Copy)]
pub(crate) enum 生成の即時定数 {
    無し,
    スカイビュー条件 {
        観測半径: f32,
        太陽天頂余弦: f32,
    },
    /// 視錐台の基準の向きと観測半径・横の差分と最遠距離・縦の差分・太陽の向きを、4成分の組4つで運ぶ。
    /// 3成分のベクトルを4成分の組へ詰めるのは、シェーダー側の即時定数の構造体が16バイト境界へ並ぶためである。
    空中遠近条件 {
        基準の向きと観測半径: [f32; 4],
        横の差分と最遠距離: [f32; 4],
        縦の差分: [f32; 4],
        太陽の向き: [f32; 4],
    },
}

impl 生成の即時定数 {
    /// ディスパッチ前に書くバイト列。持たない枝では空を返し、呼び出し元が書き込みそのものを省く。
    pub(crate) fn バイト列(self) -> Vec<u8> {
        match self {
            Self::無し => Vec::new(),
            Self::スカイビュー条件 {
                観測半径, 太陽天頂余弦
            } => 実数列を並べる(&[観測半径, 太陽天頂余弦]),
            Self::空中遠近条件 {
                基準の向きと観測半径,
                横の差分と最遠距離,
                縦の差分,
                太陽の向き,
            } => {
                let mut 値一覧 = Vec::with_capacity(16);
                for 組 in [基準の向きと観測半径, 横の差分と最遠距離, 縦の差分, 太陽の向き] {
                    値一覧.extend_from_slice(&組);
                }
                実数列を並べる(&値一覧)
            }
        }
    }
}

/// f32の列をリトルエンディアンのバイト列へ並べる。シェーダー側の即時定数の宣言と同じ並びである。
fn 実数列を並べる(値一覧: &[f32]) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(値一覧.len() * 4);
    for 値 in 値一覧 {
        バイト列.extend_from_slice(&値.to_le_bytes());
    }
    バイト列
}
