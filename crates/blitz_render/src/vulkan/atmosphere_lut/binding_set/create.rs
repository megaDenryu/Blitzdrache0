//! 大気のベイク済み画像の束縛一式の生成局面。呼ばれるのは大気のベイク済み画像一式の組み立て時の1回だけである。
//! ディスクリプタを`descriptors`が、パイプラインを`pipelines`が作り、ここは2段の順序と巻き戻しだけを持つ。
//! 部分的に生成された束は呼び出し元から見えない。

mod descriptors;
mod pipelines;

use super::大気のベイク済み画像の束縛一式;
use crate::error::レンダラーエラー;
use crate::shader_bundle::大気のベイク済み画像のシェーダー一式;
use crate::vulkan::allocator::GPU資源の確保係;
use crate::vulkan::atmosphere_lut::base_resources::大気のベイク済み画像の基盤資源;

pub(super) fn 大気のベイク済み画像の束縛一式を生成する(
    確保係: &GPU資源の確保係<'_>,
    基盤: &大気のベイク済み画像の基盤資源,
    シェーダー: &大気のベイク済み画像のシェーダー一式,
) -> Result<大気のベイク済み画像の束縛一式, レンダラーエラー> {
    let device = 確保係.論理デバイス();
    let ディスクリプタ = descriptors::作る(確保係, 基盤)?;
    match pipelines::作る(確保係, &ディスクリプタ, シェーダー) {
        Ok(
            [
                透過率パイプライン,
                多重散乱パイプライン,
                スカイビューパイプライン,
                遠方環境用スカイビューパイプライン,
                空中遠近パイプライン,
            ],
        ) => Ok(大気のベイク済み画像の束縛一式 {
            透過率ディスクリプタ: ディスクリプタ.透過率,
            多重散乱ディスクリプタ: ディスクリプタ.多重散乱,
            スカイビューディスクリプタ: ディスクリプタ.スカイビュー,
            遠方環境用スカイビューディスクリプタ: ディスクリプタ.遠方環境用スカイビュー,
            空中遠近ディスクリプタ: ディスクリプタ.空中遠近,
            透過率パイプライン,
            多重散乱パイプライン,
            スカイビューパイプライン,
            遠方環境用スカイビューパイプライン,
            空中遠近パイプライン,
        }),
        Err(誤り) => {
            ディスクリプタ.破棄する(device);
            Err(誤り)
        }
    }
}
