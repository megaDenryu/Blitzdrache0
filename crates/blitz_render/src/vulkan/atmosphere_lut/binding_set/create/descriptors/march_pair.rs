//! 経路生成ディスクリプタを書き込み先の並びぶん作る工程。受け取るのは基盤資源と書き込み先ビューの並び、
//! 返すのは同じ並びのディスクリプタか、1つも残さずに巻き戻したうえでの失敗である。
//!
//! 並びで扱って途中の失敗を自分で巻き戻すのが担当であり、呼び出し元は成功したときの並びだけを見る。
//! 分岐の入れ子で扱わないのは、書き込み先が増えるたびに入れ子が1段深くなるのを避けるためである。

use ash::vk;

use crate::error::レンダラーエラー;
use crate::vulkan::atmosphere_lut::base_resources::大気のベイク済み画像の基盤資源;
use crate::vulkan::atmosphere_lut::march_descriptor::{経路生成の束縛先, 経路生成ディスクリプタ};
use crate::vulkan::sync::進行中フレーム数;

pub(super) fn 経路生成を順に作る(
    device: &ash::Device,
    基盤: &大気のベイク済み画像の基盤資源,
    シェーダー定数一覧: &[vk::Buffer; 進行中フレーム数],
    書き込み先一覧: [vk::ImageView; 2],
) -> Result<[経路生成ディスクリプタ; 2], レンダラーエラー> {
    let mut 作った: Vec<経路生成ディスクリプタ> = Vec::with_capacity(書き込み先一覧.len());
    for 書き込み先ビュー in 書き込み先一覧 {
        let 束縛先 = 経路生成の束縛先 {
            シェーダー定数一覧,
            透過率ビュー: 基盤.透過率.画像ビュー,
            多重散乱ビュー: 基盤.多重散乱.画像ビュー,
            書き込み先ビュー,
        };
        match 経路生成ディスクリプタ::生成する(device, 束縛先) {
            Ok(ディスクリプタ) => 作った.push(ディスクリプタ),
            Err(誤り) => {
                while let Some(ディスクリプタ) = 作った.pop() {
                    ディスクリプタ.破棄する(device);
                }
                return Err(誤り);
            }
        }
    }
    let 件数 = 作った.len();
    Ok(作った
        .try_into()
        .unwrap_or_else(|_| panic!("経路生成ディスクリプタを{}つ要求したのに{件数}つできた", 書き込み先一覧.len())))
}
