//! 大気散乱媒体を、コンピュートシェーダーが読むユニフォームのバイト列へ組み立てる工程。
//! 受け取るのは単位付きの媒体、返すのは`shaders/atmosphere_medium.slang`の`AtmosphereMedium`と一致するバイト列である。
//!
//! 注意: このバイト列の並びはslang側の構造体の宣言順そのものである。片方だけを変えると、
//! 半径と係数が入れ替わったまま静かにベイク済み画像が焼かれる。並びの一致はGPU読み戻し検査が代表テクセルで確かめる。

use crate::atmosphere::大気散乱媒体;
use crate::vulkan::uniform::bytes::{vec4を書き込む, ベクトル3をvec4化};

/// float4の枠の数: 半径1・消散係数3・散乱係数2・地表アルベドと非対称係数1・密度層6・定数項6。
const 枠数: usize = 19;
pub(super) const バイト長: usize = 枠数 * 16;

pub(super) fn バイト列にする(媒体: &大気散乱媒体) -> [u8; バイト長] {
    let mut バイト列 = [0u8; バイト長];
    let mut 位置 = 0usize;
    let 消散 = 媒体.消散();
    vec4を書き込む(&mut バイト列, &mut 位置, [消散.下端半径().値(), 消散.上端半径().値(), 0.0, 0.0]);
    for 成分 in 消散.成分一覧() {
        vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(係数の生値(成分.消散係数()), 0.0));
    }
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(係数の生値(媒体.レイリー散乱係数()), 0.0));
    vec4を書き込む(&mut バイト列, &mut 位置, ベクトル3をvec4化(係数の生値(媒体.ミー散乱係数()), 0.0));
    vec4を書き込む(
        &mut バイト列,
        &mut 位置,
        ベクトル3をvec4化(媒体.地表アルベド().成分(), 媒体.位相非対称係数().値()),
    );
    for 成分 in 消散.成分一覧() {
        for 層 in 成分.密度分布().層() {
            vec4を書き込む(
                &mut バイト列,
                &mut 位置,
                [層.幅().値(), 層.指数項(), 層.指数尺度().値(), 層.線形項().値()],
            );
        }
    }
    for 成分 in 消散.成分一覧() {
        for 層 in 成分.密度分布().層() {
            vec4を書き込む(&mut バイト列, &mut 位置, [層.定数項(), 0.0, 0.0, 0.0]);
        }
    }
    バイト列
}

/// GPU境界(生型境界): 逆長さの3成分を毎メートルの生値へ戻す。
fn 係数の生値(係数: crate::atmosphere::消散係数RGB) -> [f32; 3] {
    let [赤, 緑, 青] = 係数.成分();
    [赤.値(), 緑.値(), 青.値()]
}
