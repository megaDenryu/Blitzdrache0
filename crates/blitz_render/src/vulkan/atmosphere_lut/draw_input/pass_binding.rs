//! ベイク済み画像1枚ぶんの生成パスが束縛する資源。担当する工程は「どのベイク済み画像を焼くかから、パイプライン・レイアウト・
//! ディスクリプタセット・ワークグループ数・即時定数の5つを1つの入力へ組む」ことである。
//!
//! 触れるのは`束縛`と`基盤`の2つのフィールドだけであり、どのハンドルも作らず参照するだけである。
//! 焼くかどうかの判断は1つも持たない。判断は`draw_input`が済ませてから呼ぶ。

use super::描画入力の材料;
use crate::vulkan::atmosphere_lut::inputs::ワークグループ数を求める;
use crate::vulkan::atmosphere_lut::{大気のベイク済み画像の生成入力, 大気のベイク済み画像一式, 生成の即時定数};
use crate::vulkan::sync::フレームスロット添字;

impl 大気のベイク済み画像一式 {
    pub(super) fn 透過率入力(&self, フレーム添字: フレームスロット添字) -> 大気のベイク済み画像の生成入力 {
        大気のベイク済み画像の生成入力 {
            pipeline: self.束縛.透過率パイプライン.handle,
            layout: self.束縛.透過率パイプライン.layout,
            ディスクリプタセット: self.束縛.透過率セット(フレーム添字),
            ワークグループ数: ワークグループ数を求める(self.基盤.透過率.形),
            即時定数: 生成の即時定数::無し,
        }
    }

    pub(super) fn 多重散乱入力(&self, フレーム添字: フレームスロット添字) -> 大気のベイク済み画像の生成入力 {
        大気のベイク済み画像の生成入力 {
            pipeline: self.束縛.多重散乱パイプライン.handle,
            layout: self.束縛.多重散乱パイプライン.layout,
            ディスクリプタセット: self.束縛.多重散乱セット(フレーム添字),
            ワークグループ数: ワークグループ数を求める(self.基盤.多重散乱.形),
            即時定数: 生成の即時定数::無し,
        }
    }

    pub(super) fn スカイビュー入力(&self, 材料: &描画入力の材料<'_>) -> 大気のベイク済み画像の生成入力 {
        大気のベイク済み画像の生成入力 {
            pipeline: self.束縛.スカイビューパイプライン.handle,
            layout: self.束縛.スカイビューパイプライン.layout,
            ディスクリプタセット: self.束縛.スカイビューセット(材料.フレーム添字),
            ワークグループ数: ワークグループ数を求める(self.基盤.スカイビュー.形),
            即時定数: 生成の即時定数::スカイビュー条件 {
                観測半径: 材料.スカイビュー条件.観測半径(材料.媒体.消散()).値(),
                太陽天頂余弦: 材料.スカイビュー条件.太陽天頂余弦().値(),
            },
        }
    }

    pub(super) fn 空中遠近入力(&self, 材料: &描画入力の材料<'_>) -> 大気のベイク済み画像の生成入力 {
        大気のベイク済み画像の生成入力 {
            pipeline: self.束縛.空中遠近パイプライン.handle,
            layout: self.束縛.空中遠近パイプライン.layout,
            ディスクリプタセット: self.束縛.空中遠近セット(材料.フレーム添字),
            ワークグループ数: ワークグループ数を求める(self.基盤.空中遠近.形),
            即時定数: 空中遠近の押し込みを作る(材料),
        }
    }
}

/// 視錐台の3ベクトルと観測半径・最遠距離・太陽の向きを、シェーダー側の即時定数の並びへ詰める。
fn 空中遠近の押し込みを作る(材料: &描画入力の材料<'_>) -> 生成の即時定数 {
    let 条件 = 材料.空中遠近条件;
    let 向き = 条件.視錐台の向き();
    生成の即時定数::空中遠近条件 {
        基準の向きと観測半径: 四成分にする(向き.基準の成分(), 条件.観測半径(材料.媒体.消散()).値()),
        横の差分と最遠距離: 四成分にする(向き.横の差分の成分(), 条件.最遠距離().値()),
        縦の差分: 四成分にする(向き.縦の差分の成分(), 0.0),
        太陽の向き: 四成分にする(条件.太陽方向().成分(), 0.0),
    }
}

fn 四成分にする(三成分: [f32; 3], 第4成分: f32) -> [f32; 4] {
    [三成分[0], 三成分[1], 三成分[2], 第4成分]
}
