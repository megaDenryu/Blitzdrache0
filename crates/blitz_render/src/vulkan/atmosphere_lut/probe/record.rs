//! 読み戻し検査のコマンド記録。担当する工程は「本番と同じ4本の生成パスと、その後ろへ画像からバッファへのコピーを積み、
//! 1回の送信で実行して結果を読む」ことである。コピーパスの宣言そのものは`copy_pass`が持つ。
//!
//! コピーを転送パスとしてグラフへ積むのは、生成の完了とコピーの間のバリアを本番と同じ導出に任せるためである。
//! 手で書いたバリアで済ませると、検査だけが本番と違う同期の下で通ってしまう。

mod copy_pass;

use crate::error::レンダラーエラー;
use crate::vulkan::atmosphere_lut::pass;
use crate::vulkan::atmosphere_lut::{大気のベイク済み画像の描画入力, 大気のベイク済み画像の画像入力, 生成する組};
use crate::vulkan::graph;
use crate::vulkan::headless::ヘッドレスGPU環境;

use super::readback_set::受け皿一式;
use super::大気のベイク済み画像の読み戻し;

pub(super) fn 焼いて読み戻す(
    環境: &ヘッドレスGPU環境,
    入力: &大気のベイク済み画像の描画入力,
    受け皿: &受け皿一式,
) -> Result<大気のベイク済み画像の読み戻し, レンダラーエラー> {
    let device = 環境.device();
    let 生成する組::全部 {
        透過率: 透過率入力,
        多重散乱: 多重散乱入力,
        スカイビュー: スカイビュー入力,
    } = &入力.焼く組
    else {
        panic!("読み戻し検査は条件依存の3枚すべてを焼く指示で呼ばれなければならない");
    };
    let Some(空中遠近入力) = &入力.空中遠近 else {
        panic!("読み戻し検査は空中遠近も焼く指示で呼ばれなければならない");
    };
    環境.一度きりで実行する(|device, command_buffer| {
        let mut グラフ = graph::グラフ::新規();
        let 透過率 = 登録する(&mut グラフ, &入力.透過率画像);
        let 多重散乱 = 登録する(&mut グラフ, &入力.多重散乱画像);
        let スカイビュー = 登録する(&mut グラフ, &入力.スカイビュー画像);
        let 空中遠近 = 登録する(&mut グラフ, &入力.空中遠近画像);
        グラフ.パスを積む(pass::作る("透過率生成", 透過率, Vec::new(), 透過率入力));
        let 透過率を読む = vec![(透過率, graph::画像用途::コンピュート読み)];
        グラフ.パスを積む(pass::作る("多重散乱生成", 多重散乱, 透過率を読む, 多重散乱入力));
        let 二枚を読む = vec![(透過率, graph::画像用途::コンピュート読み), (多重散乱, graph::画像用途::コンピュート読み)];
        グラフ.パスを積む(pass::作る("スカイビュー生成", スカイビュー, 二枚を読む.clone(), スカイビュー入力));
        グラフ.パスを積む(pass::作る("空中遠近生成", 空中遠近, 二枚を読む, 空中遠近入力));
        コピーを積む(&mut グラフ, "透過率読み戻し", 透過率, &入力.透過率画像, 受け皿.透過率().handle);
        コピーを積む(&mut グラフ, "多重散乱読み戻し", 多重散乱, &入力.多重散乱画像, 受け皿.多重散乱().handle);
        コピーを積む(
            &mut グラフ,
            "スカイビュー読み戻し",
            スカイビュー,
            &入力.スカイビュー画像,
            受け皿.スカイビュー().handle,
        );
        コピーを積む(&mut グラフ, "空中遠近読み戻し", 空中遠近, &入力.空中遠近画像, 受け皿.空中遠近().handle);
        graph::実行する(device, command_buffer, グラフ, None);
    })?;
    Ok(大気のベイク済み画像の読み戻し {
        透過率: 受け皿.透過率().読み取る(device)?,
        多重散乱: 受け皿.多重散乱().読み取る(device)?,
        スカイビュー: 受け皿.スカイビュー().読み取る(device)?,
        空中遠近: 受け皿.空中遠近().読み取る(device)?,
    })
}

fn コピーを積む(
    グラフ: &mut graph::グラフ<'_>,
    名前: &'static str,
    ハンドル: graph::画像ハンドル,
    画像: &大気のベイク済み画像の画像入力,
    受け: ash::vk::Buffer,
) {
    グラフ.パスを積む(copy_pass::作る(名前, ハンドル, 画像.形.範囲(), 受け));
}

/// 検査は4枚すべてを1回の記録で焼くため、どの画像も「焼く画像」として登録する。
fn 登録する(グラフ: &mut graph::グラフ<'_>, 画像: &大気のベイク済み画像の画像入力) -> graph::画像ハンドル {
    グラフ.画像を登録する(
        画像.画像,
        画像.ビュー,
        graph::画像アスペクト::カラー,
        graph::大気のベイク済み画像を焼く画像の初期状態(),
        画像.形.グラフへ渡す寸法(),
    )
}
