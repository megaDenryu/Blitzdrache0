//! validation層の指摘の観測。受け取るのはウィンドウなし実行GPU環境、返すのは層を有効にできたかと指摘の件数である。
//!
//! 注意: 件数は環境の破棄より後に読む。破棄そのものが発する指摘も件数へ含めるためである。この順序を守る責任が
//! この型を単独で置く理由であり、観測を取り出す手順が1箇所にあることで呼び出し元が順序を組み替えられない。

use crate::validation_counter::検証層の状況;
use crate::vulkan::headless::ウィンドウなし実行GPU環境;

/// その実行でvalidation層を有効にできたかと、層が数えた指摘の件数。
/// 件数だけを返さないのは、層が無い機材の0件を有効な機材の0件と読み違えないためである。
pub(crate) struct 検証観測 {
    pub(crate) 状況: 検証層の状況,
    pub(crate) 件数: u64,
}

impl 検証観測 {
    /// 環境を破棄したうえで観測を返す。破棄より前にカウンタの複製を持ち出し、読むのは破棄の後である。
    pub(super) fn 環境を破棄して観測する(環境: &ウィンドウなし実行GPU環境) -> Self {
        let 状況 = 環境.検証層の状況();
        let カウンタ = 環境.検証カウンタを複製する();
        環境.破棄する();
        Self {
            状況,
            件数: カウンタ.件数を読む(),
        }
    }
}
