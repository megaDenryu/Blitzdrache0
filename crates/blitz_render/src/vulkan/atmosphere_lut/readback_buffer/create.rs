//! 読み戻しバッファの生成局面。呼ばれるのは読み戻し検査の組み立て時だけであり、以降は貸し出しと読み取りだけである。
//! 成分数ごとに違うのはテクセル1つのバイト数だけであるため、確保そのものは1つの工程が担う。

use ash::vk;

use super::half_float::{二成分のテクセルのバイト数, 四成分のテクセルのバイト数};
use super::ベイク済み画像の読み戻しバッファ;
use crate::error::レンダラーエラー;
use crate::vulkan::allocator::GPU資源の確保係;

pub(in crate::vulkan) fn 四成分で生成する(
    確保係: &GPU資源の確保係<'_>,
    テクセル数: usize,
) -> Result<ベイク済み画像の読み戻しバッファ, レンダラーエラー> {
    生成する(確保係, テクセル数, 四成分のテクセルのバイト数)
}

pub(in crate::vulkan) fn 二成分で生成する(
    確保係: &GPU資源の確保係<'_>,
    テクセル数: usize,
) -> Result<ベイク済み画像の読み戻しバッファ, レンダラーエラー> {
    生成する(確保係, テクセル数, 二成分のテクセルのバイト数)
}

fn 生成する(
    確保係: &GPU資源の確保係<'_>,
    テクセル数: usize,
    テクセルのバイト数: usize,
) -> Result<ベイク済み画像の読み戻しバッファ, レンダラーエラー> {
    let バイト数 = u64::try_from(テクセル数 * テクセルのバイト数).unwrap_or_else(|_| panic!("読み戻しバイト数がu64に収まらない"));
    let バッファ = 確保係.読み戻し先のホスト可視バッファを確保する(バイト数, vk::BufferUsageFlags::TRANSFER_DST)?;
    Ok(ベイク済み画像の読み戻しバッファ {
        バッファ,
        テクセル数,
        テクセルのバイト数,
    })
}
