//! 半精度(16ビット浮動小数)のビット列を単精度へ開く工程。受け取るのはテクセルのバイト列、返すのは4成分の単精度である。
//!
//! 自前で書くのは、この1箇所のためだけに外部クレートを増やさないためである(依存の追加は採用審査と白リストの更新を要する)。
//! 変換は指数と仮数のビットを並べ替えるだけであり、単精度は半精度の値域と精度を完全に含むため丸めは起きない。

/// 1テクセルのバイト数。R16G16B16A16_SFLOATの4成分ぶんである。
pub(super) const テクセルのバイト数: usize = 8;

pub(super) fn 単精度へ開く(バイト列: &[u8]) -> Vec<[f32; 4]> {
    バイト列
        .chunks_exact(テクセルのバイト数)
        .map(|テクセル| {
            let mut 成分 = [0.0_f32; 4];
            for (添字, 対) in テクセル.chunks_exact(2).enumerate() {
                成分[添字] = 半精度を単精度へ(u16::from_le_bytes([対[0], 対[1]]));
            }
            成分
        })
        .collect()
}

/// 半精度の16ビットを単精度へ開く。非正規化数は仮数に2の-24乗を掛けた値であり、無限大とNaNは指数を埋めて表す。
fn 半精度を単精度へ(ビット: u16) -> f32 {
    let 符号 = u32::from(ビット >> 15) << 31;
    let 指数 = u32::from((ビット >> 10) & 0x1f);
    let 仮数 = u32::from(ビット & 0x03ff);
    if 指数 == 0 {
        let 大きさ = f32::from(ビット & 0x03ff) * 非正規化数の刻み();
        return if 符号 == 0 { 大きさ } else { -大きさ };
    }
    if 指数 == 0x1f {
        return f32::from_bits(符号 | 0x7f80_0000 | (仮数 << 13));
    }
    // 半精度の指数の下駄は15、単精度は127であるため、差の112を足す。
    f32::from_bits(符号 | ((指数 + 112) << 23) | (仮数 << 13))
}

fn 非正規化数の刻み() -> f32 {
    f32::from_bits(0x3380_0000)
}
