//! 遠方環境用スカイビュー画像の1フレームぶんの束縛を組む工程。受け取るのは焼く条件、返すのは生成パス1本ぶんの
//! 入力と、グラフへ登録するための画像の姿である。焼くかどうかの判断は1つも持たない。
//!
//! 判断を持たないのは、この画像を焼くフレームが遠方環境の焼き上げの計画で決まるためである。計画は間接照明の
//! 資源が持っており、大気のベイク済み画像一式はその条件を知らないまま束縛だけを答える。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」

use super::inputs::計算の班数を求める;
use super::{
    大気のベイク済み画像の生成入力, 大気のベイク済み画像の画像入力, 大気のベイク済み画像一式, 生成の即時定数
};
use crate::atmosphere::{スカイビュー観測条件, 大気散乱媒体};
use crate::vulkan::sync::フレームスロット添字;

/// 遠方環境用スカイビューを焼く条件。観測条件が代表天頂余弦から作られていることは呼び出し元が保証する。
pub(crate) struct 遠方環境用スカイビューの焼く条件<'a> {
    pub(crate) フレーム添字: フレームスロット添字,
    pub(crate) 媒体: &'a 大気散乱媒体,
    pub(crate) スカイビュー条件: スカイビュー観測条件,
}

impl 大気のベイク済み画像一式 {
    pub(crate) fn 遠方環境用スカイビューの生成入力(
        &self,
        条件: &遠方環境用スカイビューの焼く条件<'_>,
    ) -> 大気のベイク済み画像の生成入力 {
        大気のベイク済み画像の生成入力 {
            pipeline: self.束縛.遠方環境用スカイビューパイプライン.handle,
            layout: self.束縛.遠方環境用スカイビューパイプライン.layout,
            ディスクリプタセット: self.束縛.遠方環境用スカイビューセット(条件.フレーム添字),
            計算の班数: 計算の班数を求める(self.基盤.遠方環境用スカイビュー.形),
            即時定数: 生成の即時定数::スカイビュー条件 {
                観測半径: 条件.スカイビュー条件.観測半径(条件.媒体.消散()).値(),
                太陽天頂余弦: 条件.スカイビュー条件.太陽天頂余弦().値(),
            },
        }
    }

    pub(crate) fn 遠方環境用スカイビューの画像入力(&self) -> 大気のベイク済み画像の画像入力 {
        self.基盤.遠方環境用スカイビュー.画像入力を作る()
    }

    /// 遠方環境の生成ディスクリプタが結ぶ読み先。空背景が読む連続なスカイビューと取り違えないよう名前で分ける。
    pub(crate) fn 遠方環境用スカイビューのビュー(&self) -> ash::vk::ImageView {
        self.基盤.遠方環境用スカイビュー.画像ビュー
    }
}
