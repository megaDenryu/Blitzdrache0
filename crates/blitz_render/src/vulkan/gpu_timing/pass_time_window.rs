//! 1つのパスのGPU時間を直近60フレームぶん保つ窓(判断30)。値オブジェクト。
//! 担当するのは標本の出し入れと、そこから平均・中央値・95パーセンタイルを求めることである。
//!
//! 平均だけを持たないのは、GPU時間の分布が跳ねる標本を含むためである。平均は跳ねた数フレームに引きずられ、
//! 条件の差を読む値として使えない。判定にはmedianとp95を使う
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」)。
//!
//! 注意: ミリ秒はf64で保持する。u64のtick差分をf32へ収める安全な変換経路が
//! 標準に無い(f64::from(u32)は可能だがf64→f32はasキャストのみで、
//! ワークスペースのas_conversions denyにより使えない)ため、f64のまま扱う。

use std::collections::VecDeque;

use crate::gpu_pass_timing::{パス時間の分布, 窓の標本数 as 窓サイズ};

pub(crate) struct パス時間の窓 {
    値一覧: VecDeque<f64>,
    合計: f64,
}

impl パス時間の窓 {
    pub(crate) fn 新規() -> Self {
        Self {
            値一覧: VecDeque::with_capacity(窓サイズ),
            合計: 0.0,
        }
    }

    pub(crate) fn 追加する(&mut self, 値ミリ秒: f64) {
        self.値一覧.push_back(値ミリ秒);
        self.合計 += 値ミリ秒;
        if self.値一覧.len() > 窓サイズ
            && let Some(古い値) = self.値一覧.pop_front()
        {
            self.合計 -= 古い値;
        }
    }

    /// 現在の窓の分布。`追加する`を1回も呼んでいない状態では呼ばれない前提(呼び出し元は初回追加と
    /// 同時にエントリを作る)だが、0除算と空の参照を避けるため件数0では全要素0の分布を返す。
    pub(crate) fn 分布(&self) -> パス時間の分布 {
        let 件数 = self.値一覧.len();
        if 件数 == 0 {
            return パス時間の分布::生成する(0.0, 0.0, 0.0, 0);
        }
        let mut 並べ替え: Vec<f64> = self.値一覧.iter().copied().collect();
        並べ替え.sort_by(f64::total_cmp);
        let 件数u16 = u16::try_from(件数).unwrap_or_else(|_| panic!("窓の標本数がu16に収まらない: {件数}"));
        パス時間の分布::生成する(self.合計 / f64::from(件数u16), 順位の値(&並べ替え, 50), 順位の値(&並べ替え, 95), 件数)
    }
}

/// 昇順に並んだ標本の百分位。最近傍順位法であり、標本が1件のときはその値そのものを返す。
/// 補間しないのは、60標本の窓で補間しても読み取れる精度が上がらず、順位の定義を1つに保つ方が読み手に確実だからである。
fn 順位の値(昇順: &[f64], 百分位: usize) -> f64 {
    let 上限 = 昇順.len().saturating_sub(1);
    let 添字 = (百分位 * 上限).div_ceil(100);
    昇順.get(添字.min(上限)).copied().unwrap_or(0.0)
}
