use super::{パス時間の窓, 窓サイズ};

#[test]
fn 標本数の上限を越えても最初の確保量を保つ() {
    let mut 窓 = パス時間の窓::新規();
    let 最初の確保量 = 窓.値一覧.capacity();
    for 標本 in 1..=120u16 {
        窓.追加する(f64::from(標本));
    }
    assert_eq!(窓.値一覧.len(), 窓サイズ);
    assert_eq!(窓.値一覧.capacity(), 最初の確保量);
    let 分布 = 窓.分布();
    assert_eq!(分布.平均ミリ秒(), 90.5);
    assert_eq!(分布.中央値ミリ秒(), 91.0);
    assert_eq!(分布.p95ミリ秒(), 118.0);
}

#[test]
fn 窓が埋まる前は存在する標本だけを並べ替える() {
    let mut 窓 = パス時間の窓::新規();
    窓.追加する(9.0);
    窓.追加する(3.0);
    窓.追加する(6.0);
    let 分布 = 窓.分布();
    assert_eq!(分布.平均ミリ秒(), 6.0);
    assert_eq!(分布.中央値ミリ秒(), 6.0);
    assert_eq!(分布.p95ミリ秒(), 9.0);
}
