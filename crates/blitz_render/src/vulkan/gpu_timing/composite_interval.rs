//! 複数のパスの1フレームぶんの合計を、1つの区間として窓へ入れる宣言と、その適用。
//!
//! これが要るのは、分位の加法性が一般に成立しないためである。
//! 区間ごとの窓からp50を採って足した値は、1フレームの合計の分布から採ったp50ではない。
//! 合計の分位を出すには、フレーム内で先に足した1つの標本を窓へ入れるしかない。
//!
//! この工程は宣言を受け取って適用するだけであり、どのパスの和をどの名前で出すかは1つも知らない。
//! 計器は描画の内容から独立に保ち、宣言の中身はそのパス名を所有する層(`vulkan::indirect_lighting`等)が持ってレンダラーの生成時に渡す。
//! ここへ特定の機能のパス名を書くと、計器がその機能を知っている層になる。

/// どのパスの和をどの名前で出すかの宣言。
pub(crate) struct 合成区間の宣言 {
    合成名: &'static str,
    /// 足し合わせる区間の名前。1つでも欠けたフレームは合成の標本を作らない。
    構成する区間名: Vec<&'static str>,
}

impl 合成区間の宣言 {
    pub(crate) fn 生成する(合成名: &'static str, 構成する区間名: Vec<&'static str>) -> Self {
        Self {
            合成名, 構成する区間名
        }
    }
}

/// 1フレームぶんの区間別の合計から、宣言どおりの合成の標本を作る。
///
/// 構成する区間が1つでも欠けていたら、その合成の標本を作らない。
/// 欠けは「そのフレームでそのパスが積まれなかった」か「クエリを読めなかった」のどちらかであり、どちらの場合も残りだけを足した値はそのフレームの合計を過小に見せる。
/// 焼かないフレームで合成の標本が1つも増えないのは正しい姿である(そのフレームに更新の費用は無い)。
pub(super) fn 適用する(宣言一覧: &[合成区間の宣言], フレーム内の合計: &[(&'static str, f64)]) -> Vec<(&'static str, f64)> {
    let mut 結果 = Vec::new();
    for 宣言 in 宣言一覧 {
        let mut 合計 = 0.0;
        let mut すべて揃った = true;
        for 区間名 in &宣言.構成する区間名 {
            match フレーム内の合計.iter().find(|(名前, _)| 名前 == 区間名) {
                Some((_, 値)) => 合計 += *値,
                None => すべて揃った = false,
            }
        }
        if すべて揃った && !宣言.構成する区間名.is_empty() {
            結果.push((宣言.合成名, 合計));
        }
    }
    結果
}

#[cfg(test)]
mod tests {
    use super::*;

    fn 宣言() -> Vec<合成区間の宣言> {
        vec![合成区間の宣言::生成する("合計", vec!["甲", "乙"])]
    }

    #[test]
    fn 構成が揃えばフレーム内で足した1標本を作る() {
        let 結果 = 適用する(&宣言(), &[("甲", 0.25), ("丙", 9.0), ("乙", 0.75)]);
        assert_eq!(結果, vec![("合計", 1.0)]);
    }

    #[test]
    fn 構成が欠けたら標本を作らない() {
        assert!(適用する(&宣言(), &[("甲", 0.25)]).is_empty());
        assert!(適用する(&宣言(), &[]).is_empty());
    }

    /// 構成が空の宣言は合計0の標本を毎フレーム作ってしまうため、標本にしない。
    #[test]
    fn 構成が空の宣言は標本を作らない() {
        let 空の宣言 = vec![合成区間の宣言::生成する("合計", Vec::new())];
        assert!(適用する(&空の宣言, &[("甲", 0.25)]).is_empty());
    }
}
