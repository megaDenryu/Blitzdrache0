//! フレーム別の生標本の記録。担当するのは、記録するかどうかの状態と、読み取り1回ぶんの値の追加である。
//!
//! 判別共用体で持つのは、記録しないことが既定であり、そのときは1要素も確保しないためである。
//! 空の列と「記録していない」を同じ表現にすると、読み手が「1フレームも読めなかった」と区別できない。
//!
//! 上限を設けないのは、上限で打ち切ると採れたはずの標本が黙って消え、後から分位を計算し直したときに
//! 報告値と合わない理由が値からは分からなくなるためである。記録は計測の起動指定でだけ始まり、
//! 通常の実行では1要素も積まない。

use crate::gpu_pass_timing::フレーム別の標本;

/// `採る`の`読み取り回数`はクエリ結果を読み取った回の通し番号である。読み取りは1フレームに1回であるため、
/// 描画したフレームの順に並ぶ。
pub(super) enum フレーム別の記録 {
    採らない,
    採る {
        読み取り回数: u64,
        標本一覧: Vec<フレーム別の標本>,
    },
}

impl フレーム別の記録 {
    pub(super) const fn 新規() -> Self {
        Self::採らない
    }

    pub(super) fn 始める(&mut self) {
        *self = Self::採る {
            読み取り回数: 0,
            標本一覧: Vec::new(),
        };
    }

    /// 読み取り1回ぶんの区間別の値を追加し、読み取りの通し番号を1つ進める。採らない状態では何もしない。
    pub(super) fn 一回ぶんを積む(&mut self, 区間別の値: &[(&'static str, f64)]) {
        let Self::採る {
            読み取り回数, 標本一覧
        } = self
        else {
            return;
        };
        for &(区間名, 経過ミリ秒) in 区間別の値 {
            標本一覧.push(フレーム別の標本::生成する(*読み取り回数, 区間名, 経過ミリ秒));
        }
        *読み取り回数 += 1;
    }

    pub(super) fn 標本一覧(&self) -> &[フレーム別の標本] {
        match self {
            Self::採らない => &[],
            Self::採る { 標本一覧, .. } => 標本一覧,
        }
    }
}
