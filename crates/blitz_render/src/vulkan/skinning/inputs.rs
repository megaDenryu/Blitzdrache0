//! スキニング一式が持つパイプラインとディスクリプタを、フレーム記録が読む1フレームぶんの描画入力へ平坦化する。
//! 呼び出しタイミング: 毎フレームの描画入力組み立て時(生成完了後・破棄前であることは保持側の`レンダラー`が保証する)。

use super::スキニング一式;
use crate::vulkan::frame::スキニング描画入力;
use crate::vulkan::sync::フレームスロット添字;

impl スキニング一式 {
    pub(crate) fn 描画入力を作る(&self, フレーム添字: フレームスロット添字) -> スキニング描画入力 {
        スキニング描画入力 {
            pipeline: self.パイプライン.handle,
            layout: self.パイプライン.layout,
            ディスクリプタセット: self.ディスクリプタ.セットのハンドル(フレーム添字),
            頂点数: self.頂点数,
            出力バッファ: self.出力バッファ(),
        }
    }
}
