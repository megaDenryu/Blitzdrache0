//! スワップチェーン寸法の変更への追従(判断38・41)。寸法に連動するHDR中間画像と光のにじみピラミッドだけを
//! 作り直し、寸法に依存しないパイプラインは保ったまま、ディスクリプタとビューを新しい画像へ束縛し直す。
//! 呼び出しタイミング: リサイズ・陳腐化でスワップチェーンを作り直した直後(GPU待機済み)。

use ash::vk;

use super::{create, ポスト処理一式};
use crate::error::レンダラーエラー;
use crate::vulkan::tracked_device::GPUデバイス;

impl ポスト処理一式 {
    /// 前提: 呼び出し時点でGPUがこれらの画像とディスクリプタを使用していないこと(device_wait_idle後)。
    ///
    /// 新しい画像を作ってから古い画像を破棄するため、画像生成が失敗しても呼び出し前の一式がそのまま残り、
    /// 保持側は一部だけが欠けた状態を見ない。交換の間だけ新旧の画像が同時に存在する分のGPUメモリを使う。
    pub(crate) fn 寸法に追従する(
        &mut self,
        device: &GPUデバイス,
        メモリプロパティ: &vk::PhysicalDeviceMemoryProperties,
        寸法: vk::Extent2D,
    ) -> Result<(), レンダラーエラー> {
        let (新hdr, 新ピラミッド) = create::画像を生成する(device, メモリプロパティ, 寸法)?;
        // ピラミッドの段数が解像度に依存するため光のにじみのディスクリプタは作り直し、明るさの圧縮は新しいビューへ束縛し直す。
        if let Err(誤り) = self.光のにじみ.ディスクリプタを作り直す(device, 新hdr.画像ビュー, &新ピラミッド) {
            新ピラミッド.破棄する(device);
            新hdr.破棄する(device);
            return Err(誤り);
        }
        self.明るさの圧縮.ビューを再束縛する(device, 新hdr.画像ビュー, 新ピラミッド.最終ビュー());
        // 注意: 旧画像の破棄は、それを読んでいたディスクリプタとビューを新画像へ差し替えた後に行う。
        self.光のにじみピラミッド.破棄する(device);
        self.hdrターゲット.破棄する(device);
        self.光のにじみピラミッド = 新ピラミッド;
        self.hdrターゲット = 新hdr;
        Ok(())
    }
}
