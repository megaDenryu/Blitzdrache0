//! バッファのバリア導出の結果。全パスの記述を宣言順に1本の一覧へ並べ、パスごとの区切りを別に持つ。
//! パスごとに一覧を分けて持つ形は、バリアを持つパスの本数だけヒープを確保する。布のパスは1刻みに100本を超えて積まれるため、この形を採らない。

use super::バッファバリア記述;

/// パス列の宣言順に並べた、パスごとのバッファバリア記述。区切りはパス1本につき1つであり、パスの本数と常に等しい。
#[derive(Debug)]
pub(crate) struct パスごとのバッファバリア {
    記述一覧: Vec<バッファバリア記述>,  // 全パスぶんの記述を宣言順に並べる
    パスごとの終わりの位置: Vec<usize>, // i本目のパスの記述は、i-1本目の終わりからi本目の終わりまで
}

impl パスごとのバッファバリア {
    pub(super) fn 空で生成する(パスの本数: usize) -> Self {
        Self {
            記述一覧: Vec::new(),
            パスごとの終わりの位置: Vec::with_capacity(パスの本数),
        }
    }

    /// 次のパスのバリア記述を末尾へ足し、そのパスの区切りを置く。記述が無いパスも区切りを1つ置く。
    pub(super) fn 次のパスのバリアを足す(&mut self, 記述: impl IntoIterator<Item = バッファバリア記述>) {
        self.記述一覧.extend(記述);
        self.パスごとの終わりの位置.push(self.記述一覧.len());
    }

    /// パスの宣言順に、各パスの直前で発行するバリア記述を取り出す。
    pub(crate) fn パス順に読み出す(&self) -> impl Iterator<Item = &[バッファバリア記述]> + '_ {
        let mut 始まり = 0;
        self.パスごとの終わりの位置.iter().map(move |&終わり| {
            let 記述 = self.記述一覧.get(始まり..終わり).unwrap_or_else(|| panic!("パスの区切りが記述一覧の範囲を外れた(実装のバグ): {始まり}..{終わり}"));
            始まり = 終わり;
            記述
        })
    }
}
