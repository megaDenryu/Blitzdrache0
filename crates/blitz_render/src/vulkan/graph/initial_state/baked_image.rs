//! 焼いた画像をグラフへ登録するときの初期状態。焼き直す画像と参照するだけの画像の2つを持つ。
//! 対象は大気のベイク済み画像と、遠方環境およびその派生表現である。どれもフレームをまたいで中身を保つ。
//!
//! 2つを同じ場所に置くのは、どちらも「焼いた画像が休むレイアウトはGENERALである」という1つの不変条件の表側と裏側で
//! あるためである。焼き直す画像だけはその不変条件を破ってよい(全テクセルを書き直すため内容を捨てられる)。
//! この不変条件は`画像用途::コンピュート読み`と`画像用途::焼いた画像の画素段参照`が
//! SHADER_READ_ONLY_OPTIMALへ移さないことで保たれている。
//!
//! 2つはレイアウトだけが違い、段とアクセスは同じである。段とアクセスが表すのは「前のフレームでこの画像へ
//! 最後に起きたこと」であり、それは焼いたか参照しただけかで変わらない同じ和になるためである。

use ash::vk;

use crate::vulkan::graph::state::画像状態;

/// そのフレームで焼き直す画像の初期状態。
///
/// 注意: layoutをUNDEFINEDにできるのは、このフレームがそのベイク済み画像の全テクセルを書き直すからである。
/// 参照するだけの画像へこの状態を使ってはならない。UNDEFINEDからの遷移は中身を捨てることを許すため、
/// 前のフレームが焼いた値が消えうる。
pub(crate) fn 焼いた画像を焼き直すときの初期状態() -> 画像状態 {
    画像状態::生成する(前フレームの最後の段(), 前フレームの最後のアクセス(), vk::ImageLayout::UNDEFINED)
}

/// そのフレームで参照するだけの画像の初期状態。
///
/// 注意: layoutはGENERALである。焼いた画像は焼き直さないフレームも中身を保つため、UNDEFINEDで内容を捨てられない。
/// GENERALに固定できるのは、最初に焼いたフレームの書き込みでGENERALへ移った後、読む用途も同じGENERALを
/// 指定しており二度と別のレイアウトへ移らないためである。
pub(crate) fn 焼いた画像を参照するだけのときの初期状態() -> 画像状態 {
    画像状態::生成する(前フレームの最後の段(), 前フレームの最後のアクセス(), vk::ImageLayout::GENERAL)
}

/// 前のフレームでこの画像を使いえた段の和。
///
/// 注意: 画素段を含めるのは、空パスと遠方環境の契約のシーン描画が画素段で焼いた画像を参照するためである。次のフレームの
/// 生成パス(コンピュート書き)が前フレームの読みを追い越さないことは、このフレーム冒頭のバリアの元の段が
/// 実際の使用を覆っていることだけが保証する(同じキューへ順に送るため、覆っていれば送信の順序で足りる)。
fn 前フレームの最後の段() -> vk::PipelineStageFlags2 {
    vk::PipelineStageFlags2::COMPUTE_SHADER | vk::PipelineStageFlags2::FRAGMENT_SHADER
}

/// 前のフレームでこの画像へ起きえたアクセスの和。生成パスの書きと、後段が参照する読みの2つである。
fn 前フレームの最後のアクセス() -> vk::AccessFlags2 {
    vk::AccessFlags2::SHADER_STORAGE_WRITE | vk::AccessFlags2::SHADER_SAMPLED_READ
}
