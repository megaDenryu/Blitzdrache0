//! 画像仮想リソースの実体台帳。グラフ構築のたびに新規作成し、外部持ち込み画像を
//! 登録する。ハンドルの解決はここでのみ行う（実行器と記録文脈が使う）。

use ash::vk;

use super::aspect::画像アスペクト;
use super::handle::画像ハンドル;

struct 画像エントリ {
    世代: u32,
    画像: vk::Image,
    画像ビュー: vk::ImageView,
    アスペクト: 画像アスペクト,
}

pub(crate) struct 画像レジストリ {
    エントリ一覧: Vec<画像エントリ>,
}

impl 画像レジストリ {
    pub(crate) fn 新規() -> Self {
        Self { エントリ一覧: Vec::new() }
    }

    /// 外部持ち込み画像を登録する。グラフは毎フレーム新規作成するため世代は常に0でよい
    /// （世代付きハンドルの型自体は、将来グラフ管理リソースを使い回す際の取り違え防止のため
    /// 用意している。参照: `_doc/設計/レンダーグラフ.md`「仮想リソース」）。
    pub(crate) fn 登録する(
        &mut self,
        画像: vk::Image,
        画像ビュー: vk::ImageView,
        アスペクト: 画像アスペクト,
    ) -> 画像ハンドル {
        let 添字 = self.エントリ一覧.len();
        let 添字u32 = u32::try_from(添字)
            .unwrap_or_else(|_| panic!("グラフへの画像登録数がu32に収まらない: {添字}"));
        let 世代 = 0;
        self.エントリ一覧.push(画像エントリ { 世代, 画像, 画像ビュー, アスペクト });
        画像ハンドル::生成する(添字u32, 世代)
    }

    fn 解決する(&self, ハンドル: 画像ハンドル) -> &画像エントリ {
        let 添字usize = usize::try_from(ハンドル.添字())
            .unwrap_or_else(|_| panic!("画像ハンドルの添字がusizeに収まらない"));
        let エントリ = self
            .エントリ一覧
            .get(添字usize)
            .unwrap_or_else(|| panic!("グラフに登録されていない画像ハンドルが解決された"));
        if エントリ.世代 != ハンドル.世代() {
            panic!("世代の異なる画像ハンドルが解決された(古いグラフのハンドルの使い回し)");
        }
        エントリ
    }

    pub(crate) fn 画像を取得する(&self, ハンドル: 画像ハンドル) -> vk::Image {
        self.解決する(ハンドル).画像
    }

    pub(crate) fn ビューを取得する(&self, ハンドル: 画像ハンドル) -> vk::ImageView {
        self.解決する(ハンドル).画像ビュー
    }

    pub(crate) fn アスペクトを取得する(&self, ハンドル: 画像ハンドル) -> 画像アスペクト {
        self.解決する(ハンドル).アスペクト
    }
}
