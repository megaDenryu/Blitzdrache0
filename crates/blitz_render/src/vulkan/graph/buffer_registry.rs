//! バッファ仮想リソースの実体台帳。画像レジストリと対になるが、バッファには
//! ビュー・アスペクトが無いためエントリはvk::Bufferのみを持つ。

use ash::vk;

use super::handle::バッファハンドル;

struct バッファエントリ {
    世代: u32,
    バッファ: vk::Buffer,
}

pub(crate) struct バッファレジストリ {
    エントリ一覧: Vec<バッファエントリ>,
}

impl バッファレジストリ {
    pub(crate) fn 新規() -> Self {
        Self { エントリ一覧: Vec::new() }
    }

    /// 外部持ち込みバッファをグラフへ登録する。グラフは毎フレーム新規作成するため
    /// 世代は常に0でよい(参照: `画像レジストリ::登録する`と同じ理由)。
    pub(crate) fn 登録する(&mut self, バッファ: vk::Buffer) -> バッファハンドル {
        let 添字 = self.エントリ一覧.len();
        let 添字u32 = u32::try_from(添字)
            .unwrap_or_else(|_| panic!("グラフへのバッファ登録数がu32に収まらない: {添字}"));
        let 世代 = 0;
        self.エントリ一覧.push(バッファエントリ { 世代, バッファ });
        バッファハンドル::生成する(添字u32, 世代)
    }

    fn 解決する(&self, ハンドル: バッファハンドル) -> &バッファエントリ {
        let 添字usize = usize::try_from(ハンドル.添字())
            .unwrap_or_else(|_| panic!("バッファハンドルの添字がusizeに収まらない"));
        let エントリ = self
            .エントリ一覧
            .get(添字usize)
            .unwrap_or_else(|| panic!("グラフに登録されていないバッファハンドルが解決された"));
        if エントリ.世代 != ハンドル.世代() {
            panic!("世代の異なるバッファハンドルが解決された(古いグラフのハンドルの使い回し)");
        }
        エントリ
    }

    pub(crate) fn バッファを取得する(&self, ハンドル: バッファハンドル) -> vk::Buffer {
        self.解決する(ハンドル).バッファ
    }
}
