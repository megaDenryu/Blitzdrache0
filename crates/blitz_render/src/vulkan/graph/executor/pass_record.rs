//! 1パスぶんのGPU命令発行: レンダリング開始/終了の挟み込みと、パス種別ごとにGPU命令をコマンドバッファへ積むコールバックの呼び出し。

use super::super::buffer_registry::バッファレジストリ;
use super::super::context::GPU命令の積み先と宣言済み資源の取り出し口;
use super::super::pass::{パス宣言, パス種別};
use super::super::pass_resource_usage::パスリソース使用;
use super::super::registry::画像レジストリ;
use super::super::rendering_setup;
use crate::vulkan::command_sink::GPU命令の積み先;

pub(super) fn パスを記録する(積み先: GPU命令の積み先<'_>, 画像レジストリ: &画像レジストリ, バッファレジストリ: &バッファレジストリ, パス: パス宣言<'_>) {
    let パス宣言 {
        名前,
        読み画像,
        書き画像,
        読みバッファ,
        書きバッファ,
        種別,
        gpu命令をコマンドバッファへ積む,
    } = パス;
    let 使用 = パスリソース使用 {
        名前,
        読み画像: &読み画像,
        書き画像: &書き画像,
        読みバッファ: &読みバッファ,
        書きバッファ: &書きバッファ,
    };
    let 積み先と取り出し口 = GPU命令の積み先と宣言済み資源の取り出し口::生成する(積み先, 画像レジストリ, バッファレジストリ, 使用);

    match 種別 {
        パス種別::グラフィックス { カラー, 深度, クリア指定 } => {
            rendering_setup::動的レンダリングを開始する(積み先, 画像レジストリ, カラー, 深度, &クリア指定);
            gpu命令をコマンドバッファへ積む(&積み先と取り出し口);
            rendering_setup::動的レンダリングを終了する(積み先);
        }
        パス種別::転送 | パス種別::コンピュート => {
            gpu命令をコマンドバッファへ積む(&積み先と取り出し口);
        }
    }
}
