use super::{ArrayVec, バッファハンドル, バッファ用途, バッファ用途列};

#[test]
fn 二件までの用途は順序を保って自身の配列に持つ() {
    let 用途 = [(バッファハンドル::生成する(0, 0), バッファ用途::コンピュート読み), (バッファハンドル::生成する(1, 0), バッファ用途::コンピュート読み書き)];
    let 一覧 = バッファ用途列::from(ArrayVec::from(用途));
    assert!(matches!(&一覧, バッファ用途列::二件まで(_)));
    assert_eq!(&*一覧, &用途);
}

#[test]
fn 用途がない布の一覧は空のスライスを返す() {
    let 一覧 = バッファ用途列::from(ArrayVec::new());
    assert!(一覧.is_empty());
}

#[test]
fn 任意件数のパスは二件を超える用途も順序を保って持つ() {
    let 用途 = vec![
        (バッファハンドル::生成する(0, 0), バッファ用途::コンピュート読み),
        (バッファハンドル::生成する(1, 0), バッファ用途::コンピュート読み),
        (バッファハンドル::生成する(2, 0), バッファ用途::コンピュート読み),
    ];
    let 一覧 = バッファ用途列::from(用途.clone());
    assert!(matches!(&一覧, バッファ用途列::任意件数(_)));
    assert_eq!(&*一覧, 用途.as_slice());
}
