//! 画像用途enum。パス宣言の読み/書きがリソースをどう使うかを表す。
//! 参照: `_doc/設計/レンダーグラフ.md`「用途(usage)」。

/// 画像がパス内でどう使われるか。バリア導出の入力になる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 画像用途 {
    /// カラーアタッチメントとして書く。
    カラー出力,
    /// 深度アタッチメントとして書く。
    深度出力,
    /// フラグメントシェーダーからサンプリングして読む。
    /// 参照: 波3のポストプロセス読み取りパスで使用予定。
    #[allow(dead_code)]
    シェーダー読みフラグメント,
    /// 転送コマンドの読み取り元。
    転送元,
    /// 転送コマンドの書き込み先（image-to-imageコピー）。
    /// 参照: 波2以降で使用予定。波1は読み戻しコピーの書き込み先がバッファのため未使用。
    #[allow(dead_code)]
    転送先,
    /// スワップチェーンへの提示。
    提示,
}
