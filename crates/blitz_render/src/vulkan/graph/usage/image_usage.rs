//! 画像用途enum。パス宣言の読み/書きがリソースをどう使うかを表す。
//! 参照: `_doc/設計/レンダーグラフ.md`「用途(usage)」。

/// 画像がパス内でどう使われるか。バリア導出の入力になる。各枝の休むレイアウトの不変条件は次のとおり。
///
/// - `カラー出力`: カラーアタッチメントとして書く
/// - `深度出力`: 深度アタッチメントとして書く
/// - `シェーダー読み画素段`: 画素段シェーダーからサンプリングして読む(明るさの圧縮パスのHDR読み等)
/// - `深度シェーダー読み`: シャドウマップを画素段シェーダーから比較サンプラーで読む(判断35)。深度アスペクトのみの
///   画像専用のレイアウト(DEPTH_READ_ONLY_OPTIMAL)を使う点が`シェーダー読み画素段`(SHADER_READ_ONLY_OPTIMAL)と異なる
/// - `コンピュート書き`: コンピュートシェーダーからストレージ画像として書く(大気のベイク済み画像の生成)。
///   レイアウトはGENERALであり、ディスクリプタセットに書いた`image_layout`と一致させる
/// - `シェーダー読みコンピュート段`: コンピュートシェーダーから読み取り専用の画像として読む(自動露出の集計が
///   HDR中間画像を読む)。レイアウトは`シェーダー読み画素段`と同じSHADER_READ_ONLY_OPTIMALであり、同じフレームで
///   画素段も読む画像が用途をまたぐたびにレイアウトを往復しない。フレームをまたいで中身を保つ焼いた画像の
///   `コンピュート読み`とは休むレイアウトの不変条件が違うため、別の用途として区別する
/// - `コンピュート読み`: コンピュートシェーダーからサンプラーで読む(多重散乱とスカイビューの生成が前段の
///   ベイク済み画像を参照する)。レイアウトはGENERALであり、ディスクリプタセットに書いた`image_layout`と一致させる。
///   SHADER_READ_ONLY_OPTIMALへ移さないのは、大気のベイク済み画像が焼き直さないフレームも中身を保つ画像であり、
///   フレームをまたいで休むレイアウトを1つに固定しないと、次フレームの初期状態を1つの値で表せなくなるためである
/// - `深度コンピュート読み`: 深度画像をコンピュートシェーダーから読み取り専用の画像として読む(局所可視性補正の
///   2つのコンピュートが深度プリパスの結果を読む)。レイアウトは`深度シェーダー読み`と同じDEPTH_READ_ONLY_OPTIMALで
///   あり、段だけが違う。深度アスペクトのみの画像はSHADER_READ_ONLY_OPTIMALを取れないため、
///   `シェーダー読みコンピュート段`と別の用途になる
/// - `コンピュート記憶読み`: 記憶画像として書いた画像を、同じコンピュート段から記憶画像として読む(両側ぼかしが
///   生の可視度を読む)。レイアウトはGENERALであり、書いた直後の画像をレイアウトを往復させずに読むためにこの
///   用途を持つ。サンプラーで読む`コンピュート読み`と区別するのは、アクセスがSHADER_STORAGE_READでありディスクリプタの
///   種別も違うためである
/// - `焼いた画像の画素段参照`: 大気のベイク済み画像を画素段シェーダーからサンプラーで読む(空パスの大気のベイク済み
///   画像方式がスカイビューと透過率を参照する)。レイアウトはGENERALであり、`シェーダー読み画素段`
///   (SHADER_READ_ONLY_OPTIMAL)と段だけが同じで別の用途である。大気のベイク済み画像だけ専用の用途を持つのは、
///   フレームをまたいで中身を保つ画像であり、休むレイアウトをGENERALに固定する不変条件が`コンピュート読み`と
///   共通だからである(参照: `graph/initial_state/atmosphere_lut.rs`)
/// - `履歴のカラー出力`: 履歴画像へカラーアタッチメントとして書く。レイアウトはGENERALであり、`カラー出力`
///   (COLOR_ATTACHMENT_OPTIMAL)と段だけが同じで別の用途である。履歴画像はフレームをまたいで中身を保ち、同じ2枚が
///   読み側と書き側を交互に入れ替わるため、休むレイアウトを1つに固定しないと初期状態を1つの値で表せなくなる
///   (参照: `graph/initial_state/temporal_reconstruction.rs`)
/// - `履歴の画素段参照`: 履歴画像を画素段シェーダーから標本器で読む。レイアウトはGENERALであり、休むレイアウトの
///   不変条件は`履歴のカラー出力`と共通である
/// - `転送元`: 転送コマンドの読み取り元
/// - `転送先`: 転送コマンドの書き込み先。検収が合成深度をホスト可視バッファから深度画像へ書き戻すときに使う
///   (参照: `vulkan/depth_injection/pass.rs`)
/// - `提示`: スワップチェーンへの提示
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 画像用途 {
    カラー出力,
    深度出力,
    シェーダー読み画素段,
    深度シェーダー読み,
    コンピュート書き,
    シェーダー読みコンピュート段,
    コンピュート読み,
    深度コンピュート読み,
    コンピュート記憶読み,
    焼いた画像の画素段参照,
    履歴のカラー出力,
    履歴の画素段参照,
    転送元,
    転送先,
    提示,
}
