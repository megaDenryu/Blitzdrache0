//! 画像用途enum。パス宣言の読み/書きがリソースをどう使うかを表す。
//! 参照: `_doc/設計/レンダーグラフ.md`「用途(usage)」。

/// 画像がパス内でどう使われるか。バリア導出の入力になる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 画像用途 {
    /// カラーアタッチメントとして書く。
    カラー出力,
    /// 深度アタッチメントとして書く。
    深度出力,
    /// フラグメントシェーダーからサンプリングして読む(トーンマップパスのHDR読み等)。
    シェーダー読みフラグメント,
    /// シャドウマップをフラグメントシェーダーから比較サンプラーで読む(判断35)。
    /// 深度アスペクトのみの画像専用のレイアウト(DEPTH_READ_ONLY_OPTIMAL)を使う点が
    /// `シェーダー読みフラグメント`(SHADER_READ_ONLY_OPTIMAL)と異なる。
    深度シェーダー読み,
    /// コンピュートシェーダーからストレージ画像として書く(大気LUTの生成)。
    /// レイアウトはGENERALであり、ディスクリプタセットに書いた`image_layout`と一致させる。
    コンピュート書き,
    /// コンピュートシェーダーからサンプラーで読む(多重散乱とスカイビューの生成が前段のLUTを引く)。
    /// レイアウトはGENERALであり、ディスクリプタセットに書いた`image_layout`と一致させる。
    /// SHADER_READ_ONLY_OPTIMALへ移さないのは、大気LUTが焼き直さないフレームも中身を保つ画像であり、
    /// フレームをまたいで休むレイアウトを1つに固定しないと、次フレームの初期状態を1つの値で表せなくなるためである。
    コンピュート読み,
    /// 大気LUTをフラグメントシェーダーからサンプラーで読む(空パスの大気LUT腕がスカイビューと透過率を引く)。
    /// レイアウトはGENERALであり、`シェーダー読みフラグメント`(SHADER_READ_ONLY_OPTIMAL)と段だけが同じで別の用途である。
    /// 大気LUTだけ専用の用途を持つのは、フレームをまたいで中身を保つ画像であり、休むレイアウトをGENERALに
    /// 固定する不変条件が`コンピュート読み`と共通だからである(参照: `graph/initial_state/atmosphere_lut.rs`)。
    大気LUTフラグメント読み,
    /// 転送コマンドの読み取り元。
    転送元,
    /// 転送コマンドの書き込み先（image-to-imageコピー）。
    /// 参照: 波2以降で使用予定。波1は読み戻しコピーの書き込み先がバッファのため未使用。
    #[allow(dead_code)]
    転送先,
    /// スワップチェーンへの提示。
    提示,
}
