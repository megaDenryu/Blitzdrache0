//! バッファ用途enum。画像用途と対になる型。
//!
//! 参照: `_doc/設計/レンダーグラフ.md`。波2のGPU粒子トイでコンピュート書き・
//! 頂点段シェーダー読みを使う。それ以外の変種は波2時点で未使用のため個別に許可する。
//!
//! 枝ごとの背景:
//! - `画素段シェーダー読み`: 画素段シェーダーからストレージバッファとして読む(明るさの圧縮がGPU上の露出状態を読む)。`頂点段シェーダー読み`と段だけが違う別の同期状態を持つため、別の用途として区別する。
//! - `頂点段シェーダー読み`: 頂点シェーダー段からストレージバッファとして読む(SV_VertexIDでの粒子位置読み等)。`頂点読み`(頂点入力バインドのVERTEX_ATTRIBUTE_READ)とは異なる同期状態を持つため別の用途として区別する。
//! - 注意: `消去の書き込み`は`転送先`と段が違う。埋める操作はCOPY段でなくCLEAR段で走るため、COPY段のバリアでは前フレームの埋めとの書き込みどうしの競合を安全化できない。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum バッファ用途 {
    頂点読み, // 頂点入力バインドとして読む(スキン済み頂点バッファ等。判断44)。
    #[allow(dead_code)]
    インデックス読み,
    #[allow(dead_code)]
    シェーダー定数読み,
    コンピュート読み,
    コンピュート書き,
    コンピュート読み書き, // コンピュートシェーダーからストレージバッファとして読み書きする(布のgather反復等。判断54)。
    画素段シェーダー読み, // 画素段シェーダーからストレージバッファとして読む。
    頂点段シェーダー読み, // 頂点シェーダー段からストレージバッファとして読む。
    #[allow(dead_code)]
    転送元,
    #[allow(dead_code)]
    転送先,
    消去の書き込み, // 消去コマンドでバッファ全体を埋める(自動露出のヒストグラムを毎フレーム0へ戻す)。
}
