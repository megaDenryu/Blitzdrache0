//! グラフィックスパスが深度を書き込む先の指定。追跡するハンドル・描画先ビュー・深度領域を1つの値で持つ。
//! カメラ深度は逆Z、光源影深度は標準Zであり、領域が消去値を決める。

use ash::vk;

use super::handle::画像ハンドル;

/// グラフィックスパスの深度アタッチメントの指定。追跡はハンドル単位で行い、実際に描く先だけを層ビューで絞る。
/// 配列画像の1層だけへ描く距離区分別のシャドウ記録がこの絞りを使い、グラフの側は配列全体を1資源として保守的に追跡する。
#[derive(Clone, Copy)]
pub(crate) struct 深度アタッチメント {
    pub(crate) ハンドル: 画像ハンドル,
    層ビュー: Option<vk::ImageView>,
    領域: 深度領域,
}

#[derive(Clone, Copy)]
enum 深度領域 {
    カメラ,
    光源影,
}

impl 深度アタッチメント {
    /// 逆Zのカメラ深度を、レジストリに登録した単層ビューへ描く。
    pub(crate) fn カメラ(ハンドル: 画像ハンドル) -> Self {
        Self {
            ハンドル,
            層ビュー: None,
            領域: 深度領域::カメラ,
        }
    }

    /// 標準Zの光源影深度を、配列画像の1層だけを指すビューへ描く。
    pub(crate) fn 光源影の層(ハンドル: 画像ハンドル, 層ビュー: vk::ImageView) -> Self {
        Self {
            ハンドル,
            層ビュー: Some(層ビュー),
            領域: 深度領域::光源影,
        }
    }

    pub(crate) fn 描画先ビュー(self, 既定: vk::ImageView) -> vk::ImageView {
        self.層ビュー.unwrap_or(既定)
    }

    pub(crate) const fn 消去値(self) -> f32 {
        match self.領域 {
            深度領域::カメラ => 0.0,
            深度領域::光源影 => 1.0,
        }
    }
}
