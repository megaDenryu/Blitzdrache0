//! グラフィックスパスが深度を書き込む先の指定。どのハンドルを追跡し、どのビューへ描くかの2つを1つの値で持つ。
//! 配列画像の1層だけへ描く帯別のシャドウ記録がこの分離を要る(追跡は配列全体、描画先は1層)。

use ash::vk;

use super::handle::画像ハンドル;

/// グラフィックスパスの深度アタッチメントの指定。追跡はハンドル単位で行い、実際に描く先だけを層ビューで絞る。
/// 配列画像の1層だけへ描く帯別のシャドウ記録がこの絞りを使い、グラフの側は配列全体を1資源として保守的に追跡する。
#[derive(Clone, Copy)]
pub(crate) struct 深度アタッチメント {
    pub(crate) ハンドル: 画像ハンドル,
    層ビュー: Option<vk::ImageView>,
}

impl 深度アタッチメント {
    /// レジストリに登録したビューへそのまま描く。単層の深度バッファはこちらを使う。
    pub(crate) fn 全体(ハンドル: 画像ハンドル) -> Self {
        Self {
            ハンドル, 層ビュー: None
        }
    }

    /// 配列画像の1層だけを指すビューへ描く。
    pub(crate) fn 層(ハンドル: 画像ハンドル, 層ビュー: vk::ImageView) -> Self {
        Self {
            ハンドル,
            層ビュー: Some(層ビュー),
        }
    }

    pub(crate) fn 描画先ビュー(self, 既定: vk::ImageView) -> vk::ImageView {
        self.層ビュー.unwrap_or(既定)
    }
}
