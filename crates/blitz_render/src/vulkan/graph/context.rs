//! GPU命令をコマンドバッファへ積むクロージャに渡す内部型。宣言済みハンドルの参照とコマンドバッファ取得だけを許す
//! （判断28: 宣言=真実。参照: `_doc/設計/レンダーグラフ.md`「パス」）。

use ash::vk;

use super::buffer_registry::バッファレジストリ;
use super::handle::{バッファハンドル, 画像ハンドル};
use super::registry::画像レジストリ;
use crate::vulkan::command_sink::GPU命令の積み先;

pub(crate) struct GPU命令の積み先と宣言済み資源の取り出し口<'a> {
    積み先: GPU命令の積み先<'a>,
    画像レジストリ: &'a 画像レジストリ,
    バッファレジストリ: &'a バッファレジストリ,
    パス名: &'static str,
    宣言済み画像: Vec<画像ハンドル>,
    宣言済みバッファ: Vec<バッファハンドル>,
}

impl<'a> GPU命令の積み先と宣言済み資源の取り出し口<'a> {
    pub(crate) fn 生成する(
        積み先: GPU命令の積み先<'a>,
        画像レジストリ: &'a 画像レジストリ,
        バッファレジストリ: &'a バッファレジストリ,
        パス名: &'static str,
        宣言済み画像: Vec<画像ハンドル>,
        宣言済みバッファ: Vec<バッファハンドル>,
    ) -> Self {
        Self {
            積み先,
            画像レジストリ,
            バッファレジストリ,
            パス名,
            宣言済み画像,
            宣言済みバッファ,
        }
    }

    /// 積む先を貸す。パスの中身を書く工程は、この組を受け取って命令を積む。
    pub(crate) fn 積み先(&self) -> GPU命令の積み先<'a> {
        self.積み先
    }

    /// 宣言済みの画像ハンドルが指すvk::Imageを参照する。
    ///
    /// 注意: 宣言(読み/書き)に無いハンドルを渡すのはプログラムのバグ（パスが自分の
    /// 宣言していないリソースへ触れようとした）であり、ここでpanicして知らせる。
    pub(crate) fn 宣言済みの画像を参照する(&self, ハンドル: 画像ハンドル) -> vk::Image {
        if !self.宣言済み画像.contains(&ハンドル) {
            panic!("パス「{}」が宣言していない画像ハンドルを参照しようとした", self.パス名);
        }
        self.画像レジストリ.画像を取得する(ハンドル)
    }

    /// 宣言済みのバッファハンドルが指すvk::Bufferを参照する。`宣言済みの画像を参照する`と同じ
    /// 「宣言=真実」規律で、未宣言のハンドルはpanicする。
    pub(crate) fn 宣言済みのバッファを参照する(&self, ハンドル: バッファハンドル) -> vk::Buffer {
        if !self.宣言済みバッファ.contains(&ハンドル) {
            panic!("パス「{}」が宣言していないバッファハンドルを参照しようとした", self.パス名);
        }
        self.バッファレジストリ.バッファを取得する(ハンドル)
    }
}
