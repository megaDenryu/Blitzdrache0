//! グラフィックスパスのクリア指定。カラーと深度のそれぞれのloadOpを決める判別共用体である。
//! 新規描画は`クリアする`、既存内容へ追記するパス(粒子描画等)は`ロードする`、
//! 深度プリパスを積んだフレームのシーン描画は`カラーだけを消去して深度は読み込む`を選ぶ。
//! 深度の消去値は`クリアする`側の枝でのみ1.0/0固定で使う。
//!
//! 3つの枝で足りるのは、成立する組み合わせがこれだけだからである。深度だけを消去してカラーを読み込むパスは、
//! 前フレームの色の上へ描き直すことになり、このエンジンのどの段階にも当たらない。

use crate::clear_color::クリアカラー;

pub(crate) enum クリア指定 {
    クリアする { カラー: クリアカラー },
    カラーだけを消去して深度は読み込む { カラー: クリアカラー }, // カラーを消去し、深度は既に書かれた内容を読み込む。深度プリパスが書いた深度を捨てないためにシーン描画が使う
    ロードする,
}
