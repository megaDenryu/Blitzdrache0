//! そのフレームの局所光レコードを、容量以下の件数だけ並べる器。触れるのは自分の枠と件数だけであり、
//! バイト列の並びもディスクリプタも知らない。
//!
//! 固定長の枠で持つのは、件数がフレームごとに変わってもヒープ確保が起きない形を保つためである
//! (参照: CLAUDE.md「日常の性能規律」)。件数を配列の長さで表さず自分で数えるのは、容量ぶんの枠を常に確保したまま
//! 先頭から詰めるためである。

use super::capacity::局所光レコードの容量;
use super::local_content::局所光レコード内容;
use crate::error::照明問い合わせ梱包エラー;

/// 注意: 枠の先頭から件数ぶんが`Some`であり、その後ろは必ず`None`である。積む以外に枠を書く口が無いことでこれを保つ。
pub(crate) struct 局所光レコードの並び {
    枠: [Option<局所光レコード内容>; 局所光レコードの容量],
    件数: usize,
}

impl 局所光レコードの並び {
    pub(crate) fn 空で始める() -> Self {
        Self {
            枠: [None; 局所光レコードの容量],
            件数: 0,
        }
    }

    /// 容量を超える積み込みは型付きの失敗にする。公開の局所光源列が同じ上限を持つためここへは到達しないが、
    /// 到達しないことを型で示せないうちは黙って切り捨てない。
    pub(crate) fn 局所光レコードを末尾へ積む(
        &mut self, 内容: 局所光レコード内容
    ) -> Result<(), 照明問い合わせ梱包エラー> {
        if self.件数 >= 局所光レコードの容量 {
            return Err(照明問い合わせ梱包エラー::局所光レコードが容量を超えた {
                件数: self.件数 + 1,
                容量: 局所光レコードの容量,
            });
        }
        self.枠[self.件数] = Some(内容);
        self.件数 += 1;
        Ok(())
    }

    pub(crate) fn 件数(&self) -> usize {
        self.件数
    }

    pub(crate) fn 局所光レコードを先頭から順に返す(&self) -> impl Iterator<Item = &局所光レコード内容> {
        self.枠.iter().flatten()
    }
}
