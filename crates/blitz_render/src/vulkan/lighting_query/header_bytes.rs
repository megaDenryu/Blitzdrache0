//! 照明問い合わせヘッダをバイト列へ組み立てる工程。受け取るのはヘッダ内容、返すのは
//! shaders/lighting_query.slangのLightingQueryHeaderと同じ並びのバイト列である。
//!
//! 注意: 並びはシェーダー側の宣言順と完全に一致させること。ここを崩すと値化けとして現れる。

use super::header_content::{ヘッダの間接照明, 照明問い合わせヘッダ内容};

/// バイト長: uint3個(12) + float1個(4) + float4個(16) = 32。
/// 太陽方向を4成分の区画へ置くのは、3成分の値が16バイト境界へそろえられる規約に合わせ、余白を並びの上に見せるためである。
pub(crate) const バイト長: usize = 32;

/// 太陽方向の3成分が始まる位置。4つ目の成分の区画は使わない。
const 太陽方向の開始位置: usize = 16;

pub(crate) fn バイト列にする(内容: &照明問い合わせヘッダ内容) -> [u8; バイト長] {
    let mut バイト列 = [0u8; バイト長];
    バイト列[0..4].copy_from_slice(&内容.方向光件数.to_le_bytes());
    バイト列[4..8].copy_from_slice(&内容.局所光件数.to_le_bytes());
    バイト列[8..12].copy_from_slice(&真偽をuintにする(内容.照明が有効か).to_le_bytes());
    間接照明を書く(&mut バイト列, &内容.間接照明);
    バイト列
}

/// 選ばれた枝の区画だけへ書く。もう一方の区画は0のまま残り、その枝の画素段はそこを1度も読まない。
fn 間接照明を書く(バイト列: &mut [u8; バイト長], 間接照明: &ヘッダの間接照明) {
    match 間接照明 {
        ヘッダの間接照明::定数近似の係数(係数) => バイト列[12..16].copy_from_slice(&係数.to_le_bytes()),
        ヘッダの間接照明::遠方環境の太陽方向(太陽方向) => {
            for (番号, 成分) in 太陽方向.成分().into_iter().enumerate() {
                let 開始 = 太陽方向の開始位置 + 番号 * 4;
                バイト列[開始..開始 + 4].copy_from_slice(&成分.to_le_bytes());
            }
        }
    }
}

fn 真偽をuintにする(値: bool) -> u32 {
    if 値 { 1 } else { 0 }
}

/// ヘッダのバイト長と全区画の開始位置を数値で固定する検査。2つのレコード列の並びは`layout_tests`が別に見る。
/// ここが枝ごとに分かれているのは、ヘッダだけが判別共用体から2通りの並びを作るためである。
#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used)]

    use super::{バイト列にする, ヘッダの間接照明, 照明問い合わせヘッダ内容};
    use crate::distant_environment::ワールドの太陽方向;

    /// 定数近似の枝。選ばなかった太陽方向の区画が0で残ることも同時に固定する。
    #[test]
    fn 定数近似のヘッダの各値が決めた開始位置へ並ぶ() {
        let バイト列 = バイト列にする(&ヘッダを組む(ヘッダの間接照明::定数近似の係数(0.25)));
        assert_eq!(バイト列.len(), 32);
        assert_eq!(uintを読む(&バイト列, 0), 3);
        assert_eq!(uintを読む(&バイト列, 4), 5);
        assert_eq!(uintを読む(&バイト列, 8), 1);
        assert_eq!(f32を読む(&バイト列, 12), 0.25);
        assert_eq!(バイト列[16..32], [0u8; 16]);
    }

    /// 遠方環境の枝。選ばなかった定数間接近似の係数の区画が0で残ることも同時に固定する。
    #[test]
    fn 遠方環境のヘッダは太陽方向を16バイト目から並べる() {
        let 太陽方向 = ワールドの太陽方向::生成する(0.0, 3.0, 4.0).unwrap();
        let バイト列 = バイト列にする(&ヘッダを組む(ヘッダの間接照明::遠方環境の太陽方向(太陽方向)));
        assert_eq!(f32を読む(&バイト列, 12), 0.0);
        assert_eq!(f32を読む(&バイト列, 16), 0.0);
        assert_eq!(f32を読む(&バイト列, 20), 0.6);
        assert_eq!(f32を読む(&バイト列, 24), 0.8);
    }

    fn ヘッダを組む(間接照明: ヘッダの間接照明) -> 照明問い合わせヘッダ内容 {
        照明問い合わせヘッダ内容 {
            方向光件数: 3,
            局所光件数: 5,
            照明が有効か: true,
            間接照明,
        }
    }

    fn f32を読む(バイト列: &[u8], 位置: usize) -> f32 {
        f32::from_le_bytes(バイト列[位置..位置 + 4].try_into().unwrap())
    }

    fn uintを読む(バイト列: &[u8], 位置: usize) -> u32 {
        u32::from_le_bytes(バイト列[位置..位置 + 4].try_into().unwrap())
    }
}
