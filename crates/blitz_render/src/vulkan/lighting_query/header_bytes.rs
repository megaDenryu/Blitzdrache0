//! 照明問い合わせヘッダをバイト列へ組み立てる工程。受け取るのはヘッダ内容、返すのは
//! shaders/lighting_query.slangのLightingQueryHeaderと同じ並びのバイト列である。
//!
//! 注意: 並びはシェーダー側の宣言順と完全に一致させること。ここを崩すと値化けとして現れる。

use super::header_content::{ヘッダの間接照明, 照明問い合わせヘッダ内容};
use crate::clustered_lighting::クラスタ写像;

#[cfg(test)]
mod header_layout_tests;

/// バイト長: uint3個(12) + float1個(4) + float4が1個(16) + uint4が2個(32) + float4が1個(16) = 80。
/// 太陽方向とクラスタ写像を16バイトの区画へそろえるのは、3成分以下の値が16バイト境界を跨がない規約に合わせ、
/// 余白を並びの上に見せるためである。
pub(crate) const バイト長: usize = 80;

/// 太陽方向の3成分が始まる位置。4つ目の成分の区画は使わない。
const 太陽方向の開始位置: usize = 16;
/// クラスタ格子の分割数(横・縦・奥行き)が始まる位置。4つ目の区画は使わない。
const 分割数の開始位置: usize = 32;
/// クラスタ写像が見る画面の画素数(横・縦)が始まる位置。3つ目と4つ目の区画は使わない。
const 画面の画素数の開始位置: usize = 48;
/// 奥行きの近と遠、視野の半角の正接の横と縦がこの順で並ぶ位置。
const 奥行き範囲と視野の開始位置: usize = 64;

pub(crate) fn バイト列にする(内容: &照明問い合わせヘッダ内容) -> [u8; バイト長] {
    let mut バイト列 = [0u8; バイト長];
    バイト列[0..4].copy_from_slice(&内容.方向光件数.to_le_bytes());
    バイト列[4..8].copy_from_slice(&内容.局所光件数.to_le_bytes());
    バイト列[8..12].copy_from_slice(&真偽をuintにする(内容.照明が有効か).to_le_bytes());
    間接照明を書く(&mut バイト列, &内容.間接照明);
    クラスタ写像を書く(&mut バイト列, 内容.クラスタ写像);
    バイト列
}

/// 選ばれた枝の区画だけへ書く。もう一方の区画は0のまま残り、その枝の画素段はそこを1度も読まない。
fn 間接照明を書く(バイト列: &mut [u8; バイト長], 間接照明: &ヘッダの間接照明) {
    match 間接照明 {
        ヘッダの間接照明::定数近似の係数(係数) => バイト列[12..16].copy_from_slice(&係数.to_le_bytes()),
        ヘッダの間接照明::遠方環境の太陽方向(太陽方向) => {
            for (番号, 成分) in 太陽方向.成分().into_iter().enumerate() {
                実数を書く(バイト列, 太陽方向の開始位置 + 番号 * 4, 成分);
            }
        }
    }
}

/// GPU境界(生値境界): 分割数と画素数と奥行きと正接を生値へ戻すのはこの1箇所だけである。
fn クラスタ写像を書く(バイト列: &mut [u8; バイト長], 写像: クラスタ写像) {
    let 分割数 = 写像.分割数();
    for (番号, 値) in [分割数.横(), 分割数.縦(), 分割数.奥行き()].into_iter().enumerate() {
        符号なし整数を書く(バイト列, 分割数の開始位置 + 番号 * 4, 値);
    }
    let 画面 = 写像.画面の寸法();
    符号なし整数を書く(バイト列, 画面の画素数の開始位置, 画面.幅());
    符号なし整数を書く(バイト列, 画面の画素数の開始位置 + 4, 画面.高さ());
    let 奥行き範囲 = 写像.奥行き範囲();
    let 正接 = 写像.視野の半角の正接();
    let 四つ組 = [奥行き範囲.近().値(), 奥行き範囲.遠().値(), 正接.横(), 正接.縦()];
    for (番号, 値) in 四つ組.into_iter().enumerate() {
        実数を書く(バイト列, 奥行き範囲と視野の開始位置 + 番号 * 4, 値);
    }
}

fn 実数を書く(バイト列: &mut [u8; バイト長], 開始: usize, 値: f32) {
    バイト列[開始..開始 + 4].copy_from_slice(&値.to_le_bytes());
}

fn 符号なし整数を書く(バイト列: &mut [u8; バイト長], 開始: usize, 値: u32) {
    バイト列[開始..開始 + 4].copy_from_slice(&値.to_le_bytes());
}

fn 真偽をuintにする(値: bool) -> u32 {
    if 値 { 1 } else { 0 }
}
