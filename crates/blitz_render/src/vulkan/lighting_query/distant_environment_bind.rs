//! 遠方環境の3つの画像を全スロットのセットへ結ぶ局面。呼ばれるのはレンダラー生成時の1回だけであり、
//! 以降のフレームは束縛先が変わらないため結び直さない。触れるのは束縛レイアウトの枝と遠方環境のサンプラーと
//! 各スロットのセットだけである。
//!
//! 生成の局面と分けるのは、呼ばれる時点が違うためである。3つの画像を持つのは描画段階資源であり、
//! それが組み上がるのはこの束が作られた後である。束の生成でまとめて結べないのはそのためである。

use super::照明問い合わせ資源束;
use crate::vulkan::descriptor::lighting_set::distant_environment::遠方環境の束縛先;
use crate::vulkan::descriptor::照明問い合わせのセットの書き込み先;

impl 照明問い合わせ資源束 {
    /// 遠方環境の束縛先を全スロットへ結ぶ。
    ///
    /// 注意: 束縛先の有無と束縛レイアウトの枝は、どちらも同じ照明問い合わせ契約から導かれるため必ず一致する。
    /// 一致しないのは呼び出し元が2つの導出を別々に持ってしまった状態であり、宣言した束縛先を空のまま使う
    /// (または存在しない番号へ書く)実行時の未定義動作へ進むため、その手前で落とす。
    pub(crate) fn 遠方環境の画像を結ぶ(&self, device: &ash::Device, 束縛先: Option<遠方環境の束縛先>) {
        match (self.束縛レイアウト.遠方環境の画像を結ぶか(), 束縛先, &self.遠方環境サンプラー) {
            (false, None, None) => (),
            (true, Some(束縛先), Some(サンプラー)) => {
                for スロット in &self.スロット一覧 {
                    照明問い合わせのセットの書き込み先::生成する(device, スロット.セット).遠方環境の3つの画像を結ぶ(束縛先, サンプラー);
                }
            }
            _ => panic!("照明問い合わせのセットの束縛レイアウトと遠方環境の束縛先が食い違う(契約からの導出が2つに割れている)"),
        }
    }
}
