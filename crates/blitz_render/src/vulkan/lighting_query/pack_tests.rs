//! 梱包の入力検査の試験が共有する素材と、2つの関心への振り分け。件数の一致と境界は`count_tests`、
//! 可視性が指せる影の資源の範囲は`visibility_tests`が見る。
//!
//! 素材をここへ置くのは、どちらの試験も「1件ぶんの正常なヘッダとレコード」を土台に、
//! 1箇所だけを崩した入力を作るからである。

#![allow(clippy::unwrap_used)]

mod count_tests;
mod visibility_tests;

use blitz_math::メートル;

use super::pack::照明問い合わせのバイト列を組み立てる;
use super::{
    ヘッダの間接照明, 局所光レコードの並び, 局所光レコード内容, 方向光レコード内容, 照明問い合わせヘッダ内容
};
use crate::clustered_lighting::{
    クラスタの奥行き範囲, クラスタ写像, クラスタ格子の分割数, 影響半径, 視野の半角の正接
};
use crate::error::照明問い合わせ梱包エラー;
use crate::extent::ウィンドウ寸法;
use crate::frame_lighting::直接光の可視性;

fn ヘッダを作る(方向光件数: u32, 局所光件数: u32) -> 照明問い合わせヘッダ内容 {
    照明問い合わせヘッダ内容 {
        方向光件数,
        局所光件数,
        照明が有効か: true,
        間接照明: ヘッダの間接照明::定数近似の係数(0.1),
        クラスタ写像: クラスタ写像を作る(),
    }
}

fn クラスタ写像を作る() -> クラスタ写像 {
    クラスタ写像::生成する(
        クラスタ格子の分割数::仮置きの分割数を返す(),
        ウィンドウ寸法::生成する(640, 480),
        クラスタの奥行き範囲::生成する(メートル::生成する(0.1), メートル::生成する(200.0)).unwrap(),
        視野の半角の正接::生成する(1.0, 0.75).unwrap(),
    )
    .unwrap()
}

/// 件数ぶんの局所光を積んだ並び。件数を引数で受けるのは、境界の検査が0件と1件と容量超過を作るためである。
fn 局所光の並びを作る(件数: usize) -> 局所光レコードの並び {
    let mut 並び = 局所光レコードの並び::空で始める();
    for _ in 0..件数 {
        並び.局所光レコードを末尾へ積む(局所光を作る()).unwrap();
    }
    並び
}

fn 方向光を作る() -> 方向光レコード内容 {
    可視性を持つ方向光を作る(直接光の可視性::影なし)
}

fn 可視性を持つ方向光を作る(可視性: 直接光の可視性) -> 方向光レコード内容 {
    方向光レコード内容 {
        光へ向かう方向: [0.0, 1.0, 0.0],
        強度: 2.0,
        色: [1.0, 1.0, 1.0],
        可視性,
    }
}

fn 局所光を作る() -> 局所光レコード内容 {
    let 半径 = 影響半径::生成する(メートル::生成する(10.0)).unwrap();
    局所光レコード内容::点光として写す([1.0, 2.0, 3.0], [1.0, 1.0, 1.0], 4.0, 半径, None)
}

/// 成功したバイト列は`Debug`を持たないため、失敗の取り出しを`unwrap_err`に頼らずここで畳む。
fn 誤りを取り出す(
    ヘッダ: &照明問い合わせヘッダ内容,
    方向光一覧: &[方向光レコード内容],
    局所光一覧: &局所光レコードの並び,
) -> 照明問い合わせ梱包エラー {
    match 照明問い合わせのバイト列を組み立てる(ヘッダ, 方向光一覧, 局所光一覧) {
        Ok(_) => panic!("整合しない入力が通ってしまった"),
        Err(誤り) => 誤り,
    }
}

fn f32を読む(バイト列: &[u8], 位置: usize) -> f32 {
    f32::from_le_bytes(バイト列[位置..位置 + 4].try_into().unwrap())
}
