//! 方向光レコードと局所光レコードについて、CPU側のバイト長と全フィールドの開始位置を数値で固定する検査。
//! ヘッダの並びは枝ごとに2通りあるため`header_bytes`が自分の中で見る。
//! シェーダー側の宣言との一致は`shader_struct_tests`が別に見る。ここが崩れると値化けとして絵に出る。
//!
//! 方向光の方向の符号が「表面から光へ向かう」規約へ反転していることもここで固定する。反転を落とすと光の当たる面が裏返るが、真っ暗な絵にはならず気づきにくい。
//! 多段影の資源添字に0以外を置かないのは、現行の影資源が1組しかなく、梱包が非0を型付きで拒むためである(受理範囲の検査は`pack_tests`が持つ)。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::{directional_bytes, local_bytes, 局所光レコード内容, 方向光レコード内容};
use crate::clustered_lighting::影響半径;
use crate::frame_lighting::直接光の可視性;
use crate::lighting_input::{光強度, 光色, 方向光入力};

#[test]
fn 方向光レコードの各値が決めた開始位置へ並ぶ() {
    let 内容 = 方向光レコード内容 {
        光へ向かう方向: [10.0, 11.0, 12.0],
        強度: 13.0,
        色: [20.0, 21.0, 22.0],
        可視性: 直接光の可視性::多段影を指す(0),
    };
    let バイト列 = directional_bytes::バイト列にする(&内容);
    assert_eq!(バイト列.len(), 48);
    assert_eq!(f32を読む(&バイト列, 0), 10.0);
    assert_eq!(f32を読む(&バイト列, 12), 13.0);
    assert_eq!(f32を読む(&バイト列, 16), 20.0);
    assert_eq!(uintを読む(&バイト列, 32), 1);
    assert_eq!(uintを読む(&バイト列, 36), 0);
}

#[test]
fn 影なしの方向光は可視性の種別0を持つ() {
    let 内容 = 方向光レコード内容 {
        光へ向かう方向: [0.0, 1.0, 0.0],
        強度: 1.0,
        色: [1.0, 1.0, 1.0],
        可視性: 直接光の可視性::影なし,
    };
    assert_eq!(uintを読む(&directional_bytes::バイト列にする(&内容), 32), 0);
}

#[test]
fn 方向光レコードの方向は入力の符号を反転した値になる() {
    let 色 = 光色::生成する(1.0, 1.0, 1.0).unwrap();
    let 強度 = 光強度::生成する(1.0).unwrap();
    let 入力 = 方向光入力::生成する(0.0, -1.0, 0.0, 色, 強度).unwrap();
    let 内容 = 方向光レコード内容::方向光入力から写す(入力, 直接光の可視性::影なし);
    let 入力の向き = 入力.方向();
    for (成分, 値) in 内容.光へ向かう方向.iter().enumerate() {
        assert_eq!(*値, -入力の向き[成分]);
    }
}

#[test]
fn 局所光レコードの各値が決めた開始位置へ並ぶ() {
    let 半径 = 影響半径::生成する(メートル::生成する(44.0)).unwrap();
    let 内容 = 局所光レコード内容::点光として写す([30.0, 31.0, 32.0], [40.0, 41.0, 42.0], 43.0, 半径);
    let バイト列 = local_bytes::バイト列にする(&内容);
    assert_eq!(バイト列.len(), 64);
    assert_eq!(f32を読む(&バイト列, 0), 30.0);
    assert_eq!(f32を読む(&バイト列, 16), 40.0);
    assert_eq!(f32を読む(&バイト列, 28), 43.0);
    assert_eq!(uintを読む(&バイト列, 32), 0);
    assert_eq!(f32を読む(&バイト列, 48), 44.0);
}

/// この版の書き込みは常に影無しである。値の読み書きが揃うのは点光源の影を入れる段であり、
/// それまで影の有無が黙って立つことがないことをここで固定する。
#[test]
fn 局所光レコードの影の欄はどの入力でも影無しになる() {
    let 半径 = 影響半径::生成する(メートル::生成する(5.0)).unwrap();
    let 内容 = 局所光レコード内容::点光として写す([0.0, 0.0, 0.0], [1.0, 1.0, 1.0], 2.0, 半径);
    let バイト列 = local_bytes::バイト列にする(&内容);
    assert_eq!(uintを読む(&バイト列, 52), 0);
    assert_eq!(uintを読む(&バイト列, 56), 0);
    assert_eq!(uintを読む(&バイト列, 60), 0);
}

fn f32を読む(バイト列: &[u8], 位置: usize) -> f32 {
    f32::from_le_bytes(バイト列[位置..位置 + 4].try_into().unwrap())
}

fn uintを読む(バイト列: &[u8], 位置: usize) -> u32 {
    u32::from_le_bytes(バイト列[位置..位置 + 4].try_into().unwrap())
}
