//! 局所光レコードについて、CPU側のバイト長と全フィールドの開始位置を数値で固定する検査。
//! シェーダー側の宣言との一致は`shader_struct_tests`が別に見る。ここが崩れると値化けとして絵に出る。
//!
//! 影の欄を割り当ての有無で見るのは、影を落とさない灯が番兵の添字でなく「持たない」ことで表されるためである
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断k」)。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::record_byte_read::{f32を読む, uintを読む};
use super::{local_bytes, 局所光レコード内容};
use crate::clustered_lighting::影響半径;
use crate::point_light_shadow::影資源添字;

#[test]
fn 局所光レコードの各値が決めた開始位置へ並ぶ() {
    let 半径 = 影響半径::生成する(メートル::生成する(44.0)).unwrap();
    let 内容 = 局所光レコード内容::点光として写す([30.0, 31.0, 32.0], [40.0, 41.0, 42.0], 43.0, 半径, None);
    let バイト列 = local_bytes::バイト列にする(&内容);
    assert_eq!(バイト列.len(), 64);
    assert_eq!(f32を読む(&バイト列, 0), 30.0);
    assert_eq!(f32を読む(&バイト列, 16), 40.0);
    assert_eq!(f32を読む(&バイト列, 28), 43.0);
    assert_eq!(uintを読む(&バイト列, 32), 0);
    assert_eq!(f32を読む(&バイト列, 48), 44.0);
}

/// 影の割り当てを持たない灯は影の有無が0になり、添字の欄も0で残る(番兵ではない)。
/// 影の割り当てを持つ灯だけが有無を立て、その立方体の番号を書く。
#[test]
fn 局所光レコードの影の欄は割り当ての有無で切り替わる() {
    let 半径 = 影響半径::生成する(メートル::生成する(5.0)).unwrap();
    let 影なし = local_bytes::バイト列にする(&局所光レコード内容::点光として写す(
        [0.0, 0.0, 0.0],
        [1.0, 1.0, 1.0],
        2.0,
        半径,
        None,
    ));
    assert_eq!(uintを読む(&影なし, 52), 0);
    assert_eq!(uintを読む(&影なし, 56), 0);
    assert_eq!(uintを読む(&影なし, 60), 0);
    let 添字 = 影資源添字::宣言の順番から生成する(2).unwrap();
    let 影あり = local_bytes::バイト列にする(&局所光レコード内容::点光として写す(
        [0.0, 0.0, 0.0],
        [1.0, 1.0, 1.0],
        2.0,
        半径,
        Some(添字),
    ));
    assert_eq!(uintを読む(&影あり, 52), 1);
    assert_eq!(uintを読む(&影あり, 56), 2);
    assert_eq!(uintを読む(&影あり, 60), 0);
}
