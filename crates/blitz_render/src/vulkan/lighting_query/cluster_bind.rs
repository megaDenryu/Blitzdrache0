//! 選別のコンピュートが生成側のセットへ結ぶ、スロットごとのバッファの組を配る局面。触れるのはスロット一覧の
//! 読み取りだけであり、生成側のセットの形も番号も知らない。
//!
//! 呼ばれるのはレンダラー生成時の1回だけである。バッファは生成時に1度だけ作られ、スワップチェーン再構築でも
//! 作り直されないため、結び直しの局面を持たない(局所可視度の画像が寸法に連動して結び直すのと対になる)。

use super::照明問い合わせ資源束;
use crate::vulkan::descriptor::照明問い合わせのバッファ組;

impl 照明問い合わせ資源束 {
    /// スロットの並びの順にバッファの組を返す。並びの位置がそのままフレームスロットの添字である。
    pub(crate) fn クラスタ選別が読むバッファ組を全スロットぶん返す(&self) -> Vec<照明問い合わせのバッファ組> {
        self.スロット一覧.iter().map(super::slot_resources::スロット資源::バッファ組).collect()
    }
}
