//! 容量を超えた梱包をディスクリプタへ書く前に落とす判定の材料を配ることである。
//!
//! 容量を確保済みのバッファの要素数として固定するのは、件数0のフレームでも0バイトのバッファを作らないためである
//! (Vulkanは0バイトのバッファを作れず、件数で確保し直すとフレームごとの再確保になる)。
//! 順5の多光源では局所光の容量をクラスタの設計とセットで上げる。

/// 方向光レコード列の要素数。現行の直接光は方向光1件である。
pub(crate) const 方向光レコードの容量: usize = 1;

/// 局所光レコード列の要素数。現行の直接光は点光源1件である。
pub(crate) const 局所光レコードの容量: usize = 1;
