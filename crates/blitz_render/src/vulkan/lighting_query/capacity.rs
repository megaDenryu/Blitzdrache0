//! 照明問い合わせのレコード列が1フレームスロットで持てる件数。担当するのは容量の値と、
//! 容量を超えた梱包をディスクリプタへ書く前に落とす判定の材料を配ることである。
//!
//! 容量を確保済みのバッファの要素数として固定するのは、件数0のフレームでも0バイトのバッファを作らないためである
//! (Vulkanは0バイトのバッファを作れず、件数で確保し直すとフレームごとの再確保になる)。

use crate::lighting_input::局所光源列;

/// 方向光レコード列の要素数。現行の直接光は方向光1件である。
pub(crate) const 方向光レコードの容量: usize = 1;

/// 局所光レコード列の要素数。世界が宣言できる件数の上限をそのまま読むのは、宣言できた光を梱包が拒む状態を
/// 作らないためである。値と64件にした根拠は`crates/blitz_render/src/lighting_input/local_lights.rs`が持つ。
pub(crate) const 局所光レコードの容量: usize = 局所光源列::上限件数;

/// 照明問い合わせのセットが持つ多段影の資源の組数。現行は1組しかないため、方向光が指せる資源添字は0だけである。
/// 順5で影の資源が配列になったときにこの数を上げる。上げる前に非0を受理すると、GPUは黙って組0を読み、
/// 「別の影を見ているつもりの光」が同じ影で描かれる。
pub(crate) const 多段影資源の組数: u32 = 1;
