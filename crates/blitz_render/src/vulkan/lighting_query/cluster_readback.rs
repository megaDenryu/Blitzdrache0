//! 選別のコンピュートが書いたクラスタ格子の2本をホストへ読み戻す局面。呼ばれるのは検収の実行が求めたときだけであり、
//! 本番のフレーム経路は1度も通らない。
//!
//! 注意: 進行中のフレームがこの2本を書いている最中に読むと中身が定まらないため、呼び出し元はGPUの待機を済ませてから呼ぶ。
//!
//! 語の列を区間表と添字列へ意味づけるのがここである。並びの正本は`shaders/lighting_query_records.slang`の
//! `ClusterCell`(開始位置と件数の2つ)であり、その並びを知るのがこのモジュールだけになるようにしてある。

use ash::vk;

use super::cluster_buffers::格子と光添字列のバイト数;
use super::照明問い合わせ資源束;
use crate::clustered_lighting::セルの光の区間;
use crate::error::レンダラーエラー;
use crate::vulkan::readback::語列を読み戻す;
use crate::vulkan::sync::フレームスロット添字;
use crate::vulkan::tracked_device::GPUデバイス;
use crate::vulkan::transfer::転送実行環境;

/// 読み戻したクラスタ格子の中身。区間表と添字列の2つで1つの答えになるため、別々に返さない。
pub(crate) struct クラスタ格子の読み戻し {
    pub(crate) 区間一覧: Vec<セルの光の区間>,
    pub(crate) 光添字列: Vec<u32>,
}

impl 照明問い合わせ資源束 {
    /// そのスロットの5本のバッファ。この局面だけがクラスタ格子の2本を引くために読む。
    fn スロットのバッファ組(
        &self,
        フレーム添字: フレームスロット添字,
    ) -> crate::vulkan::descriptor::照明問い合わせのバッファ組 {
        self.スロット一覧[フレーム添字.配列添字()].バッファ組()
    }

    /// 前提: 呼び出し時点でGPUがこのスロットのクラスタ格子を使用していないこと(device_wait_idle後)。
    pub(crate) fn クラスタ格子を読み戻す(
        &self,
        device: &GPUデバイス,
        メモリプロパティ: &vk::PhysicalDeviceMemoryProperties,
        転送環境: &転送実行環境,
        フレーム添字: フレームスロット添字,
    ) -> Result<クラスタ格子の読み戻し, レンダラーエラー> {
        let (格子のバイト数, 光添字列のバイト数) = 格子と光添字列のバイト数();
        let バッファ組 = self.スロットのバッファ組(フレーム添字);
        let 格子の語列 = 語列を読み戻す(device, メモリプロパティ, 転送環境, バッファ組.クラスタ格子, 格子のバイト数)?;
        let 光添字列 = 語列を読み戻す(device, メモリプロパティ, 転送環境, バッファ組.クラスタ光添字列, 光添字列のバイト数)?;
        Ok(クラスタ格子の読み戻し {
            区間一覧: 区間表へ意味づける(&格子の語列),
            光添字列,
        })
    }
}

/// 2語で1つのセルを表す。先が区間の開始位置、後が件数である。
fn 区間表へ意味づける(語列: &[u32]) -> Vec<セルの光の区間> {
    語列.chunks_exact(2).map(|組| セルの光の区間::生成する(組[0], 組[1])).collect()
}
