//! 方向光レコード1件へ書き込む内容と、その内容を公開の方向光入力から作る唯一の変換点。
//! 触れるのは1件ぶんの値だけであり、列の並びも件数も知らない。
//!
//! 注意: 方向は「表面から光へ向かう」規約で持つ。公開の方向光入力が持つのは「光が進む向き」であるため、
//! ここで符号が反転する。反転する箇所をこの1つの関数へ閉じ、単体テストで固定する
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段5)。

use crate::frame_lighting::直接光の可視性;
use crate::lighting_input::方向光入力;

#[derive(Clone, Copy)]
pub(crate) struct 方向光レコード内容 {
    /// 表面から光へ向かう正規化された方向。
    pub(crate) 光へ向かう方向: [f32; 3],
    pub(crate) 強度: f32,
    /// scene-linearの色。物理単位へ校正されていないため共通のシーン線形尺度として扱う。
    pub(crate) 色: [f32; 3],
    pub(crate) 可視性: 直接光の可視性,
}

impl 方向光レコード内容 {
    pub(crate) fn 方向光入力から写す(方向光: 方向光入力, 可視性: 直接光の可視性) -> Self {
        Self {
            光へ向かう方向: 光へ向かう方向へ反転する(方向光.方向()),
            強度: 方向光.強度(),
            色: 方向光.色(),
            可視性,
        }
    }
}

/// 光が進む向きから、表面から光へ向かう向きへ反転する。符号の反転は浮動小数として厳密であり、長さを変えない。
fn 光へ向かう方向へ反転する(光が進む向き: [f32; 3]) -> [f32; 3] {
    [-光が進む向き[0], -光が進む向き[1], -光が進む向き[2]]
}
