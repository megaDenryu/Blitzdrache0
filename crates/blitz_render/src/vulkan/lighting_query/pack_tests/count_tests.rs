//! ヘッダの件数と実レコード列の関係の検査。件数0と1の境界、件数が実体より多い場合と少ない場合、
//! 容量を超えるレコード列の4つを見る。
//!
//! 件数0でもバイト列の長さが容量ぶんのまま変わらないことを見るのは、0バイトのバッファを作らない規律の裏返しである。

use super::super::capacity::{局所光レコードの容量, 方向光レコードの容量};
use super::super::pack::{局所光列のバイト長, 方向光列のバイト長, 組み立てる};
use super::{f32を読む, ヘッダを作る, 局所光を作る, 方向光を作る, 誤りを取り出す};
use crate::error::照明問い合わせ梱包エラー;

#[test]
fn 件数0でも列のバイト長は容量ぶんのまま変わらない() {
    let バイト列 = 組み立てる(&ヘッダを作る(0, 0), &[], &[]).unwrap();
    assert_eq!(バイト列.方向光列.len(), 方向光列のバイト長);
    assert_eq!(バイト列.局所光列.len(), 局所光列のバイト長);
    const { assert!(方向光列のバイト長 > 0) };
    const { assert!(局所光列のバイト長 > 0) };
    assert!(バイト列.方向光列.iter().all(|値| *値 == 0));
}

#[test]
fn 件数1のレコードが列の先頭へ並ぶ() {
    let バイト列 = 組み立てる(&ヘッダを作る(1, 1), &[方向光を作る()], &[局所光を作る()]).unwrap();
    assert_eq!(f32を読む(&バイト列.方向光列, 12), 2.0);
    assert_eq!(f32を読む(&バイト列.局所光列, 28), 4.0);
}

#[test]
fn ヘッダの件数が実レコード数より多い入力を方向光でも局所光でも型付きで拒む() {
    let 方向光の期待 = 照明問い合わせ梱包エラー::方向光の件数不整合 {
        件数: 1,
        レコード数: 0,
        容量: 方向光レコードの容量,
    };
    assert_eq!(誤りを取り出す(&ヘッダを作る(1, 0), &[], &[]), 方向光の期待);
    let 局所光の期待 = 照明問い合わせ梱包エラー::局所光の件数不整合 {
        件数: 1,
        レコード数: 0,
        容量: 局所光レコードの容量,
    };
    assert_eq!(誤りを取り出す(&ヘッダを作る(0, 1), &[], &[]), 局所光の期待);
}

#[test]
fn ヘッダの件数が実レコード数より少ない入力を方向光でも局所光でも型付きで拒む() {
    let 方向光の期待 = 照明問い合わせ梱包エラー::方向光の件数不整合 {
        件数: 0,
        レコード数: 1,
        容量: 方向光レコードの容量,
    };
    assert_eq!(誤りを取り出す(&ヘッダを作る(0, 0), &[方向光を作る()], &[]), 方向光の期待);
    let 局所光の期待 = 照明問い合わせ梱包エラー::局所光の件数不整合 {
        件数: 0,
        レコード数: 1,
        容量: 局所光レコードの容量,
    };
    assert_eq!(誤りを取り出す(&ヘッダを作る(0, 0), &[], &[局所光を作る()]), 局所光の期待);
}

#[test]
fn 容量を超えるレコード列を型付きで拒む() {
    let 過剰 = vec![方向光を作る(); 方向光レコードの容量 + 1];
    let 件数 = u32::try_from(過剰.len()).unwrap();
    let 期待 = 照明問い合わせ梱包エラー::方向光の件数不整合 {
        件数,
        レコード数: 過剰.len(),
        容量: 方向光レコードの容量,
    };
    assert_eq!(誤りを取り出す(&ヘッダを作る(件数, 0), &過剰, &[]), 期待);
}
