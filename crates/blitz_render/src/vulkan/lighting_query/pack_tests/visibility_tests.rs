//! 方向光の可視性が指せる影の資源の範囲の検査。現行の照明問い合わせのセットは多段影を1組しか持たないため、
//! 受理する資源添字は0だけである。
//!
//! 非0を通すと、CPUは「別の影を見る光」を作れたつもりになるのにGPUは黙って組0を読む。この食い違いは
//! 絵に出ないため、梱包の時点で落とす。

use super::super::capacity::多段影資源の組数;
use super::super::pack::照明問い合わせのバイト列を組み立てる;
use super::{ヘッダを作る, 可視性を持つ方向光を作る, 誤りを取り出す};
use crate::error::照明問い合わせ梱包エラー;
use crate::frame_lighting::直接光の可視性;
use crate::vulkan::lighting_query::局所光レコードの並び;

#[test]
fn 多段影の資源添字0は受理する() {
    let 方向光 = [可視性を持つ方向光を作る(直接光の可視性::多段影を指す(0))];
    assert!(照明問い合わせのバイト列を組み立てる(&ヘッダを作る(1, 0), &方向光, &局所光レコードの並び::空で始める()).is_ok());
}

#[test]
fn 現行の組数の外を指す多段影の資源添字を型付きで拒む() {
    let 範囲外 = 多段影資源の組数;
    let 方向光 = [可視性を持つ方向光を作る(直接光の可視性::多段影を指す(範囲外))];
    let 期待 = 照明問い合わせ梱包エラー::多段影の資源添字が範囲外 {
        資源添字: 範囲外,
        組数: 多段影資源の組数,
    };
    assert_eq!(誤りを取り出す(&ヘッダを作る(1, 0), &方向光, &局所光レコードの並び::空で始める()), 期待);
}

#[test]
fn 影なしの枝は資源添字を持たないため受理する() {
    let 方向光 = [可視性を持つ方向光を作る(直接光の可視性::影なし)];
    assert!(照明問い合わせのバイト列を組み立てる(&ヘッダを作る(1, 0), &方向光, &局所光レコードの並び::空で始める()).is_ok());
}
