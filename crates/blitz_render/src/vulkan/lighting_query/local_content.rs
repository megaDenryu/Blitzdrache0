//! 局所光レコード1件へ書き込む内容と、その光種の判別。触れるのは1件ぶんの値だけであり、
//! 列の並びも件数も知らない。
//!
//! 影響半径を持たないのは、現行の入力に根拠のある値が無いためである。減衰と打ち切りの方針が決まる順5で
//! レコードの版を上げて足す(参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段5)。
//! 位置はカメラ相対で持つ。方向光と違い局所光は平行移動で値が変わるため、原点を引く境界が要る。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 局所光の種別 {
    点光,
}

/// 注意: `種別`をこのモジュールの外から書けなくしてあるため、レコードを作れるのは`点光として写す`だけである。
/// 光種が点光へ閉じていることの保証地点をその1つに閉じるための可視性である。
#[derive(Clone, Copy)]
pub(crate) struct 局所光レコード内容 {
    pub(crate) カメラ相対位置: [f32; 3],
    /// scene-linearの色。物理単位へ校正されていないため共通のシーン線形尺度として扱う。
    pub(crate) 色: [f32; 3],
    pub(crate) 強度: f32,
    pub(super) 種別: 局所光の種別,
}

impl 局所光レコード内容 {
    /// 局所光レコードを作る唯一の入口。現行の局所光は点光だけであり、光種の値をここが決める。
    /// 光種が増えるのは順5で減衰と打ち切りの方針が決まるときであり、そのときにこの入口へ枝を足す。
    pub(crate) fn 点光として写す(カメラ相対位置: [f32; 3], 色: [f32; 3], 強度: f32) -> Self {
        Self {
            カメラ相対位置,
            色,
            強度,
            種別: 局所光の種別::点光,
        }
    }
}
