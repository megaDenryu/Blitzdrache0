//! 局所光レコード1件へ書き込む内容と、その光種の判別。触れるのは1件ぶんの値だけであり、
//! 列の並びも件数も知らない。
//!
//! 影の欄に値の読み書きが揃うのは着手順5の第5段階である。影資源添字を`Option`で持つのは、影を落とさない灯が
//! 番兵の添字でなく「持たない」ことで表されるためである(参照: 同文書「判断k」)。
//!
//! 影響半径を持つのは、着手順5の第2段階でレコードを64バイトへ版上げし、光が届く範囲をGPUへ運ぶようにしたためである
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断c: 局所光レコードを64バイトへ版上げし、第4の16バイト区画に半径と影を置く」)。
//! 位置はカメラ相対で持つ。方向光と違い局所光は平行移動で値が変わるため、原点を引く境界が要る。

use crate::clustered_lighting::影響半径;
use crate::point_light_shadow::影資源添字;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 局所光の種別 {
    点光,
}

/// 注意: `種別`をこのモジュールの外から書けなくしてあるため、レコードを作れるのは`点光として写す`だけである。
/// 光種が点光へ閉じていることの保証地点をその1つに閉じるための可視性である。
///
/// `色`はscene-linearで持つ。物理単位へ校正されていないため、共通のシーン線形尺度として扱う。
/// `影資源添字`を割り当てるのは局所光源列を完成させる口だけである。
#[derive(Clone, Copy)]
pub(crate) struct 局所光レコード内容 {
    pub(crate) カメラ相対位置: [f32; 3],
    pub(crate) 色: [f32; 3], // scene-linearの色
    pub(crate) 強度: f32,
    pub(crate) 影響半径: 影響半径,
    pub(crate) 影資源添字: Option<影資源添字>, // 影を落とす灯だけが持つ、立方体配列の中の立方体の番号
    pub(super) 種別: 局所光の種別,
}

impl 局所光レコード内容 {
    /// 局所光レコードを作る唯一の入口。現行の局所光は点光だけであり、光種の値をここが決める。
    /// 光種が増えるときにこの入口へ枝を足す。
    pub(crate) fn 点光として写す(
        カメラ相対位置: [f32; 3],
        色: [f32; 3],
        強度: f32,
        影響半径: 影響半径,
        影資源添字: Option<影資源添字>,
    ) -> Self {
        Self {
            カメラ相対位置,
            色,
            強度,
            影響半径,
            影資源添字,
            種別: 局所光の種別::点光,
        }
    }
}
