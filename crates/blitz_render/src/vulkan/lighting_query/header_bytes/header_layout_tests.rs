//! ヘッダのバイト長と全区画の開始位置を数値で固定する検査。2つのレコード列の並びは`layout_tests`が別に見る。
//! ここが枝ごとに分かれているのは、ヘッダだけが判別共用体から2通りの並びを作るためである。
//! クラスタ写像の4つのパラメータは枝によらず同じ位置へ並ぶため、1つの検査でまとめて固定する。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::{ヘッダの間接照明, 照明問い合わせヘッダ内容, 照明問い合わせヘッダ内容をバイト列にする};
use crate::clustered_lighting::{クラスタの奥行き範囲, クラスタ写像, クラスタ格子の分割数, 視野の半角の正接};
use crate::distant_environment::ワールドの太陽方向;
use crate::extent::ウィンドウ寸法;

/// 定数近似の枝。選ばなかった太陽方向の区画が0で残ることも同時に固定する。
#[test]
fn 定数近似のヘッダの各値が決めた開始位置へ並ぶ() {
    let バイト列 = 照明問い合わせヘッダ内容をバイト列にする(&ヘッダを組む(ヘッダの間接照明::定数近似の係数(0.25)));
    assert_eq!(バイト列.len(), 80);
    assert_eq!(uintを読む(&バイト列, 0), 3);
    assert_eq!(uintを読む(&バイト列, 4), 5);
    assert_eq!(uintを読む(&バイト列, 8), 1);
    assert_eq!(f32を読む(&バイト列, 12), 0.25);
    assert_eq!(バイト列[16..32], [0u8; 16]);
}

/// 遠方環境の枝。選ばなかった定数間接近似の係数の区画が0で残ることも同時に固定する。
#[test]
fn 遠方環境のヘッダは太陽方向を16バイト目から並べる() {
    let 太陽方向 = ワールドの太陽方向::生成する(0.0, 3.0, 4.0).unwrap();
    let バイト列 = 照明問い合わせヘッダ内容をバイト列にする(&ヘッダを組む(ヘッダの間接照明::遠方環境の太陽方向(太陽方向)));
    assert_eq!(f32を読む(&バイト列, 12), 0.0);
    assert_eq!(f32を読む(&バイト列, 16), 0.0);
    assert_eq!(f32を読む(&バイト列, 20), 0.6);
    assert_eq!(f32を読む(&バイト列, 24), 0.8);
}

/// クラスタ写像の4つのパラメータ。未使用の3区画が0で残ることも同時に固定する。
#[test]
fn クラスタ写像の各パラメータが決めた開始位置へ並ぶ() {
    let バイト列 = 照明問い合わせヘッダ内容をバイト列にする(&ヘッダを組む(ヘッダの間接照明::定数近似の係数(0.25)));
    assert_eq!(uintを読む(&バイト列, 32), 16);
    assert_eq!(uintを読む(&バイト列, 36), 8);
    assert_eq!(uintを読む(&バイト列, 40), 24);
    assert_eq!(uintを読む(&バイト列, 44), 0);
    assert_eq!(uintを読む(&バイト列, 48), 1280);
    assert_eq!(uintを読む(&バイト列, 52), 720);
    assert_eq!(バイト列[56..64], [0u8; 8]);
    assert_eq!(f32を読む(&バイト列, 64), 0.1);
    assert_eq!(f32を読む(&バイト列, 68), 500.0);
    assert_eq!(f32を読む(&バイト列, 72), 1.25);
    assert_eq!(f32を読む(&バイト列, 76), 0.75);
}

fn ヘッダを組む(間接照明: ヘッダの間接照明) -> 照明問い合わせヘッダ内容 {
    照明問い合わせヘッダ内容 {
        方向光件数: 3,
        局所光件数: 5,
        照明が有効か: true,
        間接照明,
        クラスタ写像: クラスタ写像を組む(),
    }
}

fn クラスタ写像を組む() -> クラスタ写像 {
    クラスタ写像::生成する(
        クラスタ格子の分割数::生成する(16, 8, 24).unwrap(),
        ウィンドウ寸法::生成する(1280, 720),
        クラスタの奥行き範囲::生成する(メートル::生成する(0.1), メートル::生成する(500.0)).unwrap(),
        視野の半角の正接::生成する(1.25, 0.75).unwrap(),
    )
    .unwrap()
}

fn f32を読む(バイト列: &[u8], 位置: usize) -> f32 {
    f32::from_le_bytes(バイト列[位置..位置 + 4].try_into().unwrap())
}

fn uintを読む(バイト列: &[u8], 位置: usize) -> u32 {
    u32::from_le_bytes(バイト列[位置..位置 + 4].try_into().unwrap())
}
