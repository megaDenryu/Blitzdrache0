//! 照明問い合わせヘッダへ書き込む内容。担当するのは、そのフレームの光の件数・照明の有効性・
//! 間接照明が要る1つの値という「レコード列の外側にある小値」を持つことである。
//!
//! 件数と真偽をuintで持つのは、floatの閾値判定(0.5と比べる形)をやめるためである。
//! 供給元方式の種別はここへ置かない。方式はパイプラインキーで既知になるため、枝が1つしかないtagをGPUへ先行させない
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段5)。
//!
//! 注意: フィールド順序はshaders/lighting_query.slangのLightingQueryHeaderの宣言順と完全に一致させること。

use crate::clustered_lighting::クラスタ写像;
use crate::distant_environment::ワールドの太陽方向;

/// `クラスタ写像`は画面の画素とビュー空間の奥行きからクラスタ格子のセルを決める4つのパラメータである。
/// ヘッダが運ぶのは、画素段と選別のコンピュートの両方が同じ値を読む必要があり、2箇所へ別々に定数を置くと
/// 片方だけを直した食い違いが絵にしか出ないためである
/// (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断d: クラスタ格子は画面タイルと奥行きの指数分割で作り、写像のパラメータは照明問い合わせヘッダが運ぶ」)。
/// 読み手が現れるのはクラスタの選別を入れる第3段階であり、この版の書き込みは誰にも読まれない。
pub(crate) struct 照明問い合わせヘッダ内容 {
    pub(crate) 方向光件数: u32,
    pub(crate) 局所光件数: u32,
    pub(crate) 照明が有効か: bool, // falseのときシーンの画素段はベースカラーをそのまま返す。光を0件にすることでは代用しない
    pub(crate) 間接照明: ヘッダの間接照明,
    pub(crate) クラスタ写像: クラスタ写像,
}

/// ヘッダが運ぶ間接照明の値。契約の枝ごとに意味のある値が違い、両方を同時に持つ状態も、どちらも持たない状態も無い。
///
/// レイアウトを枝で変えず両方の区画を常に置くのは、同じ`LightingQueryHeader`の宣言を2つの画素段が読むためである。
/// バイト長が枝で変わると、宣言が1つであることの意味が失われる。
///
/// 注意: 選ばれなかった側の区画には0が入る。これは既定値の適用ではなく、その枝のパイプラインが1度も読まない区画である。
/// 定数近似の画素段は太陽方向を参照せず、遠方環境の画素段は定数間接近似の係数を参照しない
/// (参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」)。
pub(crate) enum ヘッダの間接照明 {
    定数近似の係数(f32),                    // 方向も位置も問わない旧来の定数間接近似の係数
    遠方環境の太陽方向(ワールドの太陽方向), // 表面が法線と反射方向を太陽相対座標へ写すためのワールドの太陽方向
}
