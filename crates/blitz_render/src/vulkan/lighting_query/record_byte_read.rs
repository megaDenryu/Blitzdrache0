//! レコードのバイト列から数を読み出す、並びの検査だけが使う道具。担うのは開始位置からの4バイトの読み出しだけである。
//! 検査そのものは方向光と局所光のそれぞれの検査が持つ。

pub(super) fn f32を読む(バイト列: &[u8], 位置: usize) -> f32 {
    f32::from_le_bytes(四バイトを切り出す(バイト列, 位置))
}

pub(super) fn uintを読む(バイト列: &[u8], 位置: usize) -> u32 {
    u32::from_le_bytes(四バイトを切り出す(バイト列, 位置))
}

fn 四バイトを切り出す(バイト列: &[u8], 位置: usize) -> [u8; 4] {
    バイト列[位置..位置 + 4]
        .try_into()
        .unwrap_or_else(|誤り| panic!("位置{位置}から4バイトを切り出せない: {誤り}"))
}
