//! 方式ごとの反復1回のパス列。原子加算は拘束→適用の2本、グラフ彩色は色の数だけの拘束、二段階は拘束→集約の2本である。
//! 読み書きの宣言を方式ごとに正確に書くのは、バリアの導出がこの宣言だけを見るためである。

use super::dispatch::{self, 発行の指定, 発行の束縛};
use super::計測ハンドル;
use crate::vulkan::graph::{グラフ, バッファ用途};
use crate::vulkan::xpbd_bench::XPBD計測一式;
use crate::vulkan::xpbd_bench::pass_names;
use crate::vulkan::xpbd_bench::pipelines::方式の工程;

impl XPBD計測一式 {
    pub(super) fn 一回の反復を積む<'a>(
        &'a self, グラフ: &mut グラフ<'a>, ハンドル: &計測ハンドル, 束縛: 発行の束縛
    ) -> u32 {
        let 読み = バッファ用途::コンピュート読み;
        let 読み書き = バッファ用途::コンピュート読み書き;
        match self.パイプライン群.工程 {
            方式の工程::原子加算 { 拘束, 適用 } => {
                dispatch::積む(
                    グラフ,
                    束縛,
                    発行の指定 {
                        名前: pass_names::原子加算の拘束,
                        読み: vec![(ハンドル.点, 読み), (ハンドル.拘束の引数, 読み), (ハンドル.隣接の区間, 読み)],
                        書き: vec![(ハンドル.ラグランジュ乗数, 読み書き), (ハンドル.補正の累積, 読み書き)],
                        pipeline: 拘束,
                        スレッド数: self.拘束の数,
                        色の区間: None,
                    },
                );
                dispatch::積む(
                    グラフ,
                    束縛,
                    発行の指定 {
                        名前: pass_names::原子加算の適用,
                        読み: vec![],
                        書き: vec![(ハンドル.点, 読み書き), (ハンドル.補正の累積, 読み書き)],
                        pipeline: 適用,
                        スレッド数: self.点の数,
                        色の区間: None,
                    },
                );
                2
            }
            方式の工程::グラフ彩色 { 拘束 } => {
                for 区間 in &self.色の区間一覧 {
                    dispatch::積む(
                        グラフ,
                        束縛,
                        発行の指定 {
                            名前: pass_names::彩色の拘束,
                            読み: vec![(ハンドル.拘束の引数, 読み)],
                            書き: vec![(ハンドル.点, 読み書き), (ハンドル.ラグランジュ乗数, 読み書き)],
                            pipeline: 拘束,
                            スレッド数: 区間.本数,
                            色の区間: Some([区間.開始, 区間.本数]),
                        },
                    );
                }
                u32::try_from(self.色の区間一覧.len()).unwrap_or_else(|_| panic!("色の数がu32に収まらない"))
            }
            方式の工程::二段階 { 拘束, 集約 } => {
                dispatch::積む(
                    グラフ,
                    束縛,
                    発行の指定 {
                        名前: pass_names::二段階の拘束,
                        読み: vec![(ハンドル.点, 読み), (ハンドル.拘束の引数, 読み), (ハンドル.隣接の区間, 読み)],
                        書き: vec![
                            (ハンドル.ラグランジュ乗数, 読み書き),
                            (ハンドル.補正の候補, バッファ用途::コンピュート書き),
                        ],
                        pipeline: 拘束,
                        スレッド数: self.拘束の数,
                        色の区間: None,
                    },
                );
                dispatch::積む(
                    グラフ,
                    束縛,
                    発行の指定 {
                        名前: pass_names::二段階の集約,
                        読み: vec![(ハンドル.補正の候補, 読み), (ハンドル.隣接の区間, 読み), (ハンドル.隣接の項目, 読み)],
                        書き: vec![(ハンドル.点, 読み書き)],
                        pipeline: 集約,
                        スレッド数: self.点の数,
                        色の区間: None,
                    },
                );
                2
            }
        }
    }
}
