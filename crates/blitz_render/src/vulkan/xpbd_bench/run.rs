//! 計測の進行: 刻みごとに定数を書き、グラフを1回の送信で走らせ、完了を待ってタイムスタンプを読む。最後に読み戻しを1回送る。
//! 刻みごとに待つのは、提示も進行中フレームも無い検査の経路であり、刻みの合計を1フレームとして測るためである。

use super::readback::読み戻しの受け皿;
