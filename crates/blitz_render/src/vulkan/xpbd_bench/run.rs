/// 走らせて読み戻した中身。validationの観測は呼び出し元が環境の破棄の後に採る。
pub(crate) struct 読み戻しの中身 {
    pub(crate) 位置: Vec<[f32; 4]>,
    pub(crate) ラグランジュ乗数: Vec<f32>,
    pub(crate) 刻み別のgpu時間: Vec<フレーム別の標本>,
    pub(crate) gpu時間の分布一覧: Vec<(&'static str, パス時間の分布)>,
    pub(crate) バッファの合計バイト数: u64,
    pub(crate) 一刻みのディスパッチ数: u32,
}

impl XPBD計測一式 {
    pub(super) fn 走らせる(
        &self,
        環境: &ウィンドウなし実行GPU環境,
        条件: &XPBD計測の条件,
        受け皿: &読み戻しの受け皿,
    ) -> Result<読み戻しの中身, レンダラーエラー> {
        let mut 計測 = 刻みごとのGPU計測::生成する(環境, 条件.方式)?;
        let 結果 = self.計測しながら走らせる(環境, 条件, 受け皿, &mut 計測);
        計測.破棄する(環境.device());
        結果
    }

    fn 計測しながら走らせる(
        &self,
        環境: &ウィンドウなし実行GPU環境,
        条件: &XPBD計測の条件,
        受け皿: &読み戻しの受け皿,
        計測: &mut 刻みごとのGPU計測,
    ) -> Result<読み戻しの中身, レンダラーエラー> {
        let device = 環境.device();
        let mut 一刻みのディスパッチ数 = 0;
        for 刻み in &条件.刻みの定数一覧 {
            self.バッファ
                .定数を書き込む(device, &params::バイト列にする(self.点の数, self.拘束の数, 刻み))?;
            let 一時 = 環境.gpu命令を積み始める()?;
            let プール = 計測.積み始める(一時.積み先());
            let mut グラフ = graph::グラフ::新規();
            let ハンドル = self.登録する(&mut グラフ);
            一刻みのディスパッチ数 = self.一刻みを積む(&mut グラフ, &ハンドル, 条件.反復回数);
            let マッピング = graph::グラフ実行器::生成する(一時.積み先(), プール).グラフを積む(グラフ);
            一時.送信して完了を待つ()?;
            計測.刻みを読み取る(device, マッピング);
        }
        let 一時 = 環境.gpu命令を積み始める()?;
        let mut グラフ = graph::グラフ::新規();
        let ハンドル = self.登録する(&mut グラフ);
        受け皿.コピーを積む(&mut グラフ, ハンドル.点, ハンドル.ラグランジュ乗数);
        graph::グラフ実行器::生成する(一時.積み先(), None).グラフを積む(グラフ);
        一時.送信して完了を待つ()?;
        let (位置, ラグランジュ乗数) = 受け皿.読む(device)?;
        Ok(読み戻しの中身 {
            位置,
            ラグランジュ乗数,
            刻み別のgpu時間: 計測.刻み別の標本一覧(),
            gpu時間の分布一覧: 計測.分布一覧(),
            バッファの合計バイト数: self.バッファ.方式が使うバイト数(条件.方式),
            一刻みのディスパッチ数,
        })
    }
}

/// ウィンドウもスワップチェーンも作らずにGPUを初期化し、方式の工程を刻み数ぶん走らせて位置と乗数とGPU時間を読み戻す。
pub(crate) fn 走らせて読み戻す(
    素材: &XPBD計測素材,
    条件: &XPBD計測の条件,
    シェーダー: &XPBDシェーダー一式,
) -> Result<(読み戻しの中身, 検証観測), レンダラーエラー> {
    let 環境 = ウィンドウなし実行GPU環境::生成する()?;
    let 結果 = 環境で走らせる(&環境, 素材, 条件, シェーダー);
    let 観測 = 検証観測::環境を破棄して観測する(&環境);
    Ok((結果?, 観測))
}

fn 環境で走らせる(
    環境: &ウィンドウなし実行GPU環境,
    素材: &XPBD計測素材,
    条件: &XPBD計測の条件,
    シェーダー: &XPBDシェーダー一式,
) -> Result<読み戻しの中身, レンダラーエラー> {
    let device = 環境.device();
    let 確保係 = 環境.資源の確保係を貸す();
    let 転送環境 = 環境.転送実行環境を生成する()?;
    let 結果 = XPBD計測一式::生成する(ステージング経由の転送係::生成する(&確保係, &転送環境), 素材, 条件, シェーダー).and_then(|一式| {
        let 結果 = 一式.読み戻しの受け皿を確保する(&確保係).and_then(|受け皿| {
            let 結果 = 一式.走らせる(環境, 条件, &受け皿);
            受け皿.破棄する(device);
            結果
        });
        一式.破棄する(device);
        結果
    });
    転送環境.破棄する();
    結果
}
