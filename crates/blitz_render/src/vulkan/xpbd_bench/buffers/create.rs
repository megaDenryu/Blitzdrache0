//! 計測バッファの生成手順。静的な引数は素材のバイト列からステージング経由で転送し、状態は零で埋めて転送する。
//! 途中失敗時は確保済みを巻き戻す(布と同じ台帳を使う)。
//! 点とラグランジュ乗数は最後にホストへ写すため転送元の用途を足す。

use ash::vk;

use super::XPBD計測バッファ;
use crate::error::レンダラーエラー;
use crate::vulkan::allocator::巻き戻せる確保の台帳;
use crate::vulkan::transfer::ステージング経由の転送係;
use crate::xpbd_solver_bench_probe::XPBD計測素材;

use super::super::params;

/// 補正の累積は点ごとに32ビット整数3つ、補正の候補は拘束ごとにfloat4が2つである。
const 累積1点のバイト数: usize = 12;
const 候補1拘束のバイト数: usize = 32;

impl XPBD計測バッファ {
    pub(in crate::vulkan::xpbd_bench) fn 生成する(
        転送係: ステージング経由の転送係<'_>,
        素材: &XPBD計測素材,
    ) -> Result<Self, レンダラーエラー> {
        let 確保係 = 転送係.確保係();
        let mut 台帳 = 巻き戻せる確保の台帳::始める(確保係);
        let ストレージ = vk::BufferUsageFlags::STORAGE_BUFFER;
        let 読み戻せるストレージ = ストレージ | vk::BufferUsageFlags::TRANSFER_SRC;
        let 点の数 = 数へ(素材.点の数);
        let 拘束の数 = 数へ(素材.拘束の数);

        let 定数 = 台帳.積む(確保係.ホスト可視バッファを確保して書き込む(&[0u8; params::バイト長], vk::BufferUsageFlags::UNIFORM_BUFFER))?;
        let 点 = 台帳.積む(転送係.データからデバイスローカルバッファを確保する(&素材.点の状態バイト列, 読み戻せるストレージ))?;
        // 前の位置は最初の積分が位置で上書きするが、未初期化の読み(位置 − 前の位置)を避けるため位置で埋める。
        let 前の位置 = 台帳.積む(転送係.データからデバイスローカルバッファを確保する(&素材.点の状態バイト列, ストレージ))?;
        let 拘束の引数 = 台帳.積む(転送係.データからデバイスローカルバッファを確保する(&素材.拘束の引数バイト列, ストレージ))?;
        let ラグランジュ乗数 = 台帳.積む(転送係.データからデバイスローカルバッファを確保する(&vec![0u8; 拘束の数 * 4], 読み戻せるストレージ))?;
        let 補正の累積 = 台帳.積む(転送係.データからデバイスローカルバッファを確保する(&vec![0u8; 点の数 * 累積1点のバイト数], ストレージ))?;
        let 補正の候補 = 台帳.積む(転送係.データからデバイスローカルバッファを確保する(&vec![0u8; 拘束の数 * 候補1拘束のバイト数], ストレージ))?;
        let 隣接の区間 = 台帳.積む(転送係.データからデバイスローカルバッファを確保する(&素材.隣接の区間バイト列, ストレージ))?;
        let 隣接の項目 = 台帳.積む(転送係.データからデバイスローカルバッファを確保する(&素材.隣接の項目バイト列, ストレージ))?;

        Ok(Self {
            定数,
            点,
            前の位置,
            拘束の引数,
            ラグランジュ乗数,
            補正の累積,
            補正の候補,
            隣接の区間,
            隣接の項目,
        })
    }
}

fn 数へ(値: u32) -> usize {
    usize::try_from(値).unwrap_or_else(|_| panic!("数がusizeに収まらない: {値}"))
}
