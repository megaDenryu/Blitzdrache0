//! 計測の一刻みのコンピュートパス列: 積分→乗数零化→(方式ごとの反復)×反復回数。各パスはバインドと計算の発行だけで、
//! バリアはグラフのバッファ読み書き宣言から導出される。方式ごとの反復は`iteration`が持つ。
//! 積む本数を返すのは、ディスパッチ回数が評価軸の1つだからである。

mod dispatch;
mod iteration;

use super::XPBD計測一式;
use super::pass_names;
use crate::vulkan::graph::{グラフ, バッファハンドル, バッファ用途, 前フレームコンピュート読み直後状態};

/// グラフへ登録した計測バッファのハンドル。
pub(super) struct 計測ハンドル {
    pub(super) 点: バッファハンドル,
    前の位置: バッファハンドル,
    拘束の引数: バッファハンドル,
    pub(super) ラグランジュ乗数: バッファハンドル,
    補正の累積: バッファハンドル,
    補正の候補: バッファハンドル,
    隣接の区間: バッファハンドル,
    隣接の項目: バッファハンドル,
}

impl XPBD計測一式 {
    pub(super) fn 登録する<'a>(&self, グラフ: &mut グラフ<'a>) -> 計測ハンドル {
        let mut 登録 = |バッファ: &crate::vulkan::allocator::専用メモリ付きバッファ| {
            グラフ.バッファを登録する(バッファ.バッファのハンドル(), 前フレームコンピュート読み直後状態())
        };
        計測ハンドル {
            点: 登録(&self.バッファ.点),
            前の位置: 登録(&self.バッファ.前の位置),
            拘束の引数: 登録(&self.バッファ.拘束の引数),
            ラグランジュ乗数: 登録(&self.バッファ.ラグランジュ乗数),
            補正の累積: 登録(&self.バッファ.補正の累積),
            補正の候補: 登録(&self.バッファ.補正の候補),
            隣接の区間: 登録(&self.バッファ.隣接の区間),
            隣接の項目: 登録(&self.バッファ.隣接の項目),
        }
    }

    /// 固定刻み1本ぶんの工程を積み、積んだパスの本数を返す。
    pub(super) fn 一刻みを積む<'a>(&'a self, グラフ: &mut グラフ<'a>, ハンドル: &計測ハンドル, 反復回数: u32) -> u32 {
        let 束縛 = self.発行の束縛();
        dispatch::積む(
            グラフ,
            束縛,
            dispatch::発行の指定 {
                名前: pass_names::積分,
                読み: vec![],
                書き: vec![
                    (ハンドル.点, バッファ用途::コンピュート読み書き),
                    (ハンドル.前の位置, バッファ用途::コンピュート読み書き),
                ],
                pipeline: self.パイプライン群.積分,
                スレッド数: self.点の数,
                色の区間: None,
            },
        );
        dispatch::積む(
            グラフ,
            束縛,
            dispatch::発行の指定 {
                名前: pass_names::乗数零化,
                読み: vec![],
                書き: vec![(ハンドル.ラグランジュ乗数, バッファ用途::コンピュート書き)],
                pipeline: self.パイプライン群.乗数零化,
                スレッド数: self.拘束の数,
                色の区間: None,
            },
        );
        let mut 本数 = 2;
        for _ in 0..反復回数 {
            本数 += self.一回の反復を積む(グラフ, ハンドル, 束縛);
        }
        本数
    }

    fn 発行の束縛(&self) -> dispatch::発行の束縛 {
        dispatch::発行の束縛 {
            layout: self.パイプライン群.layout,
            セット: self.ディスクリプタ.セットのハンドル(),
        }
    }
}
