//! 派生表現の即時定数のバイト並びを反証可能な形で固定する。担うのは、押し込むものが無い枝が空の列を返すことと、
//! 粗さの枝が単精度1つぶんの長さでレイアウトの宣言と一致することの2つである。

#![allow(clippy::unwrap_used)]

use super::{派生表現の即時定数, 粗さの即時定数のバイト数};

#[test]
fn 押し込むものが無い枝は空の列を返す() {
    assert!(派生表現の即時定数::無し.バイト列().is_empty());
}

#[test]
fn 粗さの枝はレイアウトが宣言した枠と一致する() {
    let 長さ = 派生表現の即時定数::粗さ(0.4).バイト列().len();
    assert_eq!(u32::try_from(長さ).unwrap(), 粗さの即時定数のバイト数);
}

#[test]
fn 粗さの値がそのまま単精度として読み戻せる() {
    let バイト列 = 派生表現の即時定数::粗さ(0.6).バイト列();
    assert_eq!(f32::from_le_bytes([バイト列[0], バイト列[1], バイト列[2], バイト列[3]]), 0.6);
}
