//! ウィンドウを持たないGPUで、与えられた遠方環境の上に3つの派生表現を焼き、中身をホストへ読み戻す工程。
//! 受け取るのは遠方環境の内容と3つの解像度とシェーダー、返すのは4つの生の成分と焼いた実行の観測である。
//!
//! 遠方環境を大気から焼かずホストから与えるのは、畳み込みの正しさを解析解と突き合わせるためである。
//! 定数の環境なら拡散照度は円周率×放射輝度、鏡面畳込みはどの粗さ段も放射輝度そのものになる。大気から焼いた環境には
//! 閉じた形の答えが無く、GPUとCPUが同じ誤りを犯していても一致してしまう。
//!
//! 値オブジェクトでなく生の成分で返すのは、検査が非有限値や負の値を観測できなければならないためである。
//! 検証済みの型で返すと、まさに検査したい壊れた値が構築の時点で弾かれてしまう。
//!
//! 本番と同じパス宣言を同じレンダーグラフへ積むため、バリアの導出も本番と同じ経路を通る。

