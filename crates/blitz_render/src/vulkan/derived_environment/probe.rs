/// 焼く条件一式。引数の列が伸び続けるのを避けて1つに束ねる。
pub(crate) struct 派生表現を焼く条件<'a> {
    pub(crate) 遠方環境: &'a 遠方環境の内容,
    pub(crate) 拡散照度の解像度: 拡散照度の解像度,
    pub(crate) 鏡面畳込みの解像度: 鏡面畳込みの解像度,
    pub(crate) 反射率積分表の解像度: 反射率積分表の解像度,
    pub(crate) 拡散照度のシェーダー: &'a コンピュートシェーダー,
    pub(crate) 鏡面畳込みのシェーダー: &'a コンピュートシェーダー,
    pub(crate) 反射率積分表のシェーダー: &'a コンピュートシェーダー,
}

/// 読み戻した生の成分。立方体の3つは並びが面(層番号の順)・縦・横の順であり、鏡面畳込みはさらに段が最も外側に来る。
/// 反射率積分表は縦が外、横が速い。
pub(crate) struct 派生表現の読み戻し {
    pub(crate) 遠方環境: Vec<[f32; 4]>,
    pub(crate) 拡散照度: Vec<[f32; 4]>,
    pub(crate) 鏡面畳込み: Vec<[f32; 4]>,
    pub(crate) 反射率積分表: Vec<[f32; 2]>,
}

pub(crate) fn 派生表現をgpuで焼いて読み戻す(
    条件: 派生表現を焼く条件<'_>,
) -> Result<(派生表現の読み戻し, 検証観測), レンダラーエラー> {
    let 環境 = ウィンドウなし実行GPU環境::生成する()?;
    let 結果 = record::環境で焼く(&環境, &条件);
    let 観測 = 検証観測::環境を破棄して観測する(&環境);
    Ok((結果?, 観測))
}
