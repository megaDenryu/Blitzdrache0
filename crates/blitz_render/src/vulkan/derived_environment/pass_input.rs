//! 派生表現一式から、1本の生成パスが束縛する入力を組み立てる操作。触れるのはパイプライン・ディスクリプタ・
//! 画像の寸法・解像度の4つだけであり、どれも生成後に変わらない。呼び出し規律は「そのパスを積むと決めた後に
//! 1本ぶんだけ呼ぶ」ことであり、焼くかどうかの判断は呼び出し元が済ませてから呼ぶ。
//!
//! 鏡面畳込みの最詳細段だけは呼んではならない。その段は計算でなく遠方環境からの複製で作るため、
//! ディスクリプタセットもパイプラインも持たない。

use super::inputs::{
    派生表現の即時定数, 派生表現の生成入力, 立方体の計算の班数を求める, 表の計算の班数を求める
};
use super::派生表現一式;
use crate::distant_environment::derived::粗さ段;

impl 派生表現一式 {
    pub(in crate::vulkan) fn 拡散照度の生成入力(&self) -> 派生表現の生成入力 {
        let 画像 = &self.画像.拡散照度;
        派生表現の生成入力 {
            pipeline: self.パイプライン.拡散照度.handle,
            layout: self.パイプライン.拡散照度.layout,
            ディスクリプタセット: self.ディスクリプタ.拡散照度.set(0),
            計算の班数: 立方体の計算の班数を求める(画像.段の一辺(0), 画像.層数()),
            即時定数: 派生表現の即時定数::無し,
        }
    }

    pub(in crate::vulkan) fn 鏡面畳込みの生成入力(&self, 段: 粗さ段) -> 派生表現の生成入力 {
        let Some(添字) = 段.番号().checked_sub(1) else {
            panic!("鏡面畳込みの最詳細段に生成入力を求めた(この段は遠方環境の複製で作る)");
        };
        let 添字 = usize::try_from(添字).unwrap_or_else(|_| panic!("粗さ段の添字がusizeに収まらない"));
        let 画像 = &self.画像.鏡面畳込み;
        派生表現の生成入力 {
            pipeline: self.パイプライン.鏡面畳込み.handle,
            layout: self.パイプライン.鏡面畳込み.layout,
            ディスクリプタセット: self.ディスクリプタ.鏡面畳込み.set(添字),
            計算の班数: 立方体の計算の班数を求める(画像.段の一辺(段.番号()), 画像.層数()),
            即時定数: 派生表現の即時定数::粗さ(self.解像度.鏡面畳込み.段の粗さ(段).値()),
        }
    }

    pub(in crate::vulkan) fn 反射率積分表の生成入力(&self) -> 派生表現の生成入力 {
        派生表現の生成入力 {
            pipeline: self.パイプライン.反射率積分表.handle,
            layout: self.パイプライン.反射率積分表.layout,
            ディスクリプタセット: self.ディスクリプタ.反射率積分表.set(),
            計算の班数: 表の計算の班数を求める(self.解像度.反射率積分表.横(), self.解像度.反射率積分表.縦()),
            即時定数: 派生表現の即時定数::無し,
        }
    }
}
