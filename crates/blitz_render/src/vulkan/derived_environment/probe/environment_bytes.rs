//! 検査が与える遠方環境の中身を、GPUの画像が読むバイト並びへ詰める工程。受け取るのは倍精度の内容、
//! 返すのは半精度4成分のバイト列である。
//!
//! バイト並びをここが単独で持つのは、これがCPUの内容とGPUの画素形式の間の唯一の契約だからである。
//! 並びは面(層番号の順)が最も外、次に縦、横が最も速く、遠方環境の内容が持つ並びをそのまま写す。
//!
//! 第4成分に0を詰めるのは、遠方環境の生成シェーダーが予約として0を書くのに合わせるためである。
//! ここだけ別の値を入れると、大気から焼いた遠方環境と検査が与えた遠方環境で第4成分の意味が変わる。

use crate::distant_environment::derived::遠方環境の内容;
use crate::numeric::half_precision::単精度を半精度へ;

/// 1テクセルのバイト数。4成分の半精度である。
const テクセルのバイト数: usize = 8;

pub(super) fn 半精度のバイト列へ詰める(内容: &遠方環境の内容) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(内容.テクセル一覧().len() * テクセルのバイト数);
    for テクセル in 内容.テクセル一覧() {
        for 成分 in テクセル {
            バイト列.extend_from_slice(&単精度を半精度へ(狭める(*成分)).to_le_bytes());
        }
        バイト列.extend_from_slice(&単精度を半精度へ(0.0).to_le_bytes());
    }
    バイト列
}

fn 狭める(値: f64) -> f32 {
    glam::DVec3::splat(値).as_vec3().x
}
