//! 読み戻し検査の資源のライフサイクル。担当する工程は「ウィンドウなし実行GPUの上に遠方環境の画像と派生表現一式と
//! 書き込みバッファと4つの受け皿を順に作り、記録を1回実行し、逆順に片付ける」ことである。
//! グラフへ何をどの順で積むかは`graph_build`が持つ。
//!
//! 大気のベイク済み画像を1枚も作らないのは、この検査が遠方環境をホストから与えるためである。畳み込みの正しさは
//! 与えた環境と結果の関係だけで決まり、環境がどう作られたかに依らない。

use crate::error::レンダラーエラー;
use crate::vulkan::derived_environment::{派生表現のシェーダー一式, 派生表現の解像度一式, 派生表現一式};
use crate::vulkan::distant_environment::遠方環境の立方体画像;
use crate::vulkan::headless::ウィンドウなし実行GPU環境;

use super::readback_set::受けバッファ四点;
use super::upload::遠方環境の書き込みバッファ;
use super::{graph_build, plan, 派生表現の読み戻し, 派生表現を焼く条件};

pub(super) fn 環境で焼く(
    環境: &ウィンドウなし実行GPU環境,
    条件: &派生表現を焼く条件<'_>,
) -> Result<派生表現の読み戻し, レンダラーエラー> {
    let device = 環境.device();
    let メモリプロパティ = 環境.メモリプロパティを取得する();
    let 遠方環境 = 遠方環境の立方体画像::生成する(device, &メモリプロパティ, 条件.遠方環境.面の一辺().値())?;
    let 結果 = 遠方環境の上で焼く(環境, &遠方環境, 条件, &メモリプロパティ);
    遠方環境.破棄する(device);
    結果
}

fn 遠方環境の上で焼く(
    環境: &ウィンドウなし実行GPU環境,
    遠方環境: &遠方環境の立方体画像,
    条件: &派生表現を焼く条件<'_>,
    メモリプロパティ: &ash::vk::PhysicalDeviceMemoryProperties,
) -> Result<派生表現の読み戻し, レンダラーエラー> {
    let device = 環境.device();
    let 解像度 = 派生表現の解像度一式 {
        拡散照度: 条件.拡散照度の解像度,
        鏡面畳込み: 条件.鏡面畳込みの解像度,
        反射率積分表: 条件.反射率積分表の解像度,
    };
    let シェーダー = 派生表現のシェーダー一式 {
        拡散照度: 条件.拡散照度のシェーダー,
        鏡面畳込み: 条件.鏡面畳込みのシェーダー,
        反射率積分表: 条件.反射率積分表のシェーダー,
    };
    let 一式 = 派生表現一式::生成する(device, メモリプロパティ, 解像度, 遠方環境.配列ビュー, &シェーダー)?;
    let 結果 = 一式の上で焼く(環境, 遠方環境, &一式, 条件, メモリプロパティ);
    一式.破棄する(device);
    結果
}

fn 一式の上で焼く(
    環境: &ウィンドウなし実行GPU環境,
    遠方環境: &遠方環境の立方体画像,
    一式: &派生表現一式,
    条件: &派生表現を焼く条件<'_>,
    メモリプロパティ: &ash::vk::PhysicalDeviceMemoryProperties,
) -> Result<派生表現の読み戻し, レンダラーエラー> {
    let device = 環境.device();
    let 書き込み = 遠方環境の書き込みバッファ::生成する(device, メモリプロパティ, 条件.遠方環境)?;
    let 受け皿 = match 受けバッファ四点::生成する(device, メモリプロパティ, &plan::テクセル数を求める(条件)) {
        Ok(受け皿) => 受け皿,
        Err(誤り) => {
            書き込み.破棄する(device);
            return Err(誤り);
        }
    };
    let 拡散照度入力 = 一式.拡散照度の生成入力();
    let 鏡面畳込み入力一覧 = plan::鏡面畳込みの入力一覧(一式, 条件);
    let 反射率積分表入力 = 一式.反射率積分表の生成入力();
    let 材料 = plan::材料の材料 {
        遠方環境画像: 遠方環境,
        一式,
        書き込み元: 書き込み.handle,
        受け: 受け皿.口(),
    };
    let 積み込みの材料 = plan::材料を組む(材料, &拡散照度入力, &鏡面畳込み入力一覧, &反射率積分表入力);
    let 積み込み結果 = 環境
        .gpu命令を積み始める()
        .and_then(|一時| graph_build::パスを積んで送信し完了を待つ(一時, 積み込みの材料));
    let 結果 = 積み込み結果.and_then(|()| 受け皿.読み取る(device));
    受け皿.破棄する(device);
    書き込み.破棄する(device);
    let 読み取り = 結果?;
    Ok(派生表現の読み戻し {
        遠方環境: 読み取り.遠方環境,
        拡散照度: 読み取り.拡散照度,
        鏡面畳込み: 読み取り.鏡面畳込み,
        反射率積分表: 読み取り.反射率積分表,
    })
}
