//! 焼く条件から、記録が要る寸法・テクセル数・パスの入力を導く工程。受け取るのは条件と資源、
//! 返すのは記録の材料と受けバッファのテクセル数である。
//!
//! 導出をここへ集めるのは、同じ寸法を「受けバッファの容量」と「コピーの領域」の2箇所が要るためである。
//! 2箇所で別々に計算すると、片方だけ段の数を数え違えて確保の外へ書き込む。

use ash::vk;

use super::readback_set::受けバッファのテクセル数;
use super::resources::{受けバッファの口, 登録する画像, 積む材料};
use super::派生表現を焼く条件;
use crate::vulkan::derived_environment::{派生表現の生成入力, 派生表現一式};
use crate::vulkan::distant_environment::遠方環境の立方体画像;

/// 材料を組むのに要るものの束。引数の列が伸び続けるのを避けて1つにする。
pub(super) struct 材料の材料<'a> {
    pub(super) 遠方環境画像: &'a 遠方環境の立方体画像,
    pub(super) 一式: &'a 派生表現一式,
    pub(super) 書き込み元: vk::Buffer,
    pub(super) 受け: 受けバッファの口,
}

pub(super) fn テクセル数を求める(条件: &派生表現を焼く条件<'_>) -> 受けバッファのテクセル数 {
    let 鏡面 = 条件.鏡面畳込みの解像度;
    let 鏡面の合計 = 鏡面.全段().into_iter().map(|段| 鏡面.段の一辺(段).全テクセル数()).sum();
    受けバッファのテクセル数 {
        遠方環境: 条件.遠方環境.面の一辺().全テクセル数(),
        拡散照度: 条件.拡散照度の解像度.面の一辺().全テクセル数(),
        鏡面畳込み: 鏡面の合計,
        反射率積分表: 条件.反射率積分表の解像度.全テクセル数(),
    }
}

/// 鏡面畳込みの粗さ段のうち、計算で焼く段(最詳細段を除く全段)の生成入力。並びは段番号の昇順である。
pub(super) fn 鏡面畳込みの入力一覧(
    一式: &派生表現一式, 条件: &派生表現を焼く条件<'_>
) -> Vec<派生表現の生成入力> {
    条件
        .鏡面畳込みの解像度
        .全段()
        .into_iter()
        .filter(|段| 段.番号() > 0)
        .map(|段| 一式.鏡面畳込みの生成入力(段))
        .collect()
}

pub(super) fn 材料を組む<'a>(
    材料: 材料の材料<'a>,
    拡散照度入力: &'a 派生表現の生成入力,
    鏡面畳込み入力一覧: &'a [派生表現の生成入力],
    反射率積分表入力: &'a 派生表現の生成入力,
) -> 積む材料<'a> {
    let 拡散 = 材料.一式.拡散照度画像();
    let 鏡面 = 材料.一式.鏡面畳込み画像();
    let 表 = 材料.一式.反射率積分表の画像();
    積む材料 {
        遠方環境: 登録する画像 {
            画像: 材料.遠方環境画像.画像,
            ビュー: 材料.遠方環境画像.配列ビュー,
            寸法: 材料.遠方環境画像.グラフへ渡す寸法(),
        },
        拡散照度: 登録する画像 {
            画像: 拡散.画像,
            ビュー: 拡散.立方体ビュー,
            寸法: 拡散.グラフへ渡す寸法(),
        },
        鏡面畳込み: 登録する画像 {
            画像: 鏡面.画像,
            ビュー: 鏡面.立方体ビュー,
            寸法: 鏡面.グラフへ渡す寸法(),
        },
        反射率積分表: 登録する画像 {
            画像: 表.画像,
            ビュー: 表.ビュー,
            寸法: 表.グラフへ渡す寸法(),
        },
        遠方環境の範囲: 材料.遠方環境画像.範囲(),
        拡散照度の範囲: 拡散.段の範囲(0),
        鏡面畳込みの段ごとの範囲: (0..鏡面.段数()).map(|段| 鏡面.段の範囲(段)).collect(),
        反射率積分表の範囲: 表.範囲(),
        層数: 材料.遠方環境画像.層数(),
        書き込み元: 材料.書き込み元,
        拡散照度入力,
        鏡面畳込み入力一覧,
        反射率積分表入力,
        受け: 材料.受け,
    }
}
