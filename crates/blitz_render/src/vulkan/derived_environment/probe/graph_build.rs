//! 読み戻し検査が積むパスの並び。担当する工程は「与えられた遠方環境を書き込み、その上へ本番と同じ生成パスを
//! 積み、4つの画像をホストへ写す」ことである。
//!
//! 本番と同じパス宣言を使うのは、生成の完了とコピーの間のバリアを本番と同じ導出に任せるためである。
//! 手で書いたバリアで済ませると、検査だけが本番と違う同期の下で通ってしまう。
//!
//! 鏡面畳込みの最詳細段の複製を計算より先に積むのは、複製が画像全体を転送先のレイアウトへ移すためである。
//! 後に積むと、計算が書いた粗い段の内容が保たれることを別に確かめなければならなくなる(レイアウトの遷移は
//! 中身を保つが、複製と計算の順序が入れ替わる余地を残さないほうが読み手に優しい)。

use ash::vk;

use super::resources::積む材料;
use crate::vulkan::derived_environment::{copy_pass, pass};
use crate::vulkan::graph;

pub(super) fn 積む(材料: 積む材料<'_>) {
    let mut グラフ = graph::グラフ::新規();
    let 遠方環境 = 画像を登録する(&mut グラフ, 材料.遠方環境.画像, 材料.遠方環境.ビュー, 材料.遠方環境.寸法);
    let 拡散照度 = 画像を登録する(&mut グラフ, 材料.拡散照度.画像, 材料.拡散照度.ビュー, 材料.拡散照度.寸法);
    let 鏡面畳込み = 画像を登録する(&mut グラフ, 材料.鏡面畳込み.画像, 材料.鏡面畳込み.ビュー, 材料.鏡面畳込み.寸法);
    let 反射率積分表 = 画像を登録する(&mut グラフ, 材料.反射率積分表.画像, 材料.反射率積分表.ビュー, 材料.反射率積分表.寸法);

    グラフ.パスを積む(copy_pass::書き込みパスを作る(
        遠方環境,
        材料.遠方環境の範囲,
        材料.層数,
        材料.書き込み元,
    ));
    グラフ.パスを積む(copy_pass::最詳細段の複製を作る(
        遠方環境,
        鏡面畳込み,
        材料.遠方環境の範囲,
        材料.層数,
    ));
    let 遠方環境を読む = || vec![(遠方環境, graph::画像用途::コンピュート読み)];
    グラフ.パスを積む(pass::作る(pass::拡散照度生成のパス名, 拡散照度, 遠方環境を読む(), 材料.拡散照度入力));
    for 入力 in 材料.鏡面畳込み入力一覧 {
        グラフ.パスを積む(pass::作る(pass::鏡面畳込み生成のパス名, 鏡面畳込み, 遠方環境を読む(), 入力));
    }
    グラフ.パスを積む(pass::作る(
        pass::反射率積分表生成のパス名,
        反射率積分表,
        Vec::new(),
        材料.反射率積分表入力,
    ));

    グラフ.パスを積む(copy_pass::立方体の読み戻しを作る(
        "遠方環境読み戻し",
        遠方環境,
        vec![材料.遠方環境の範囲],
        材料.層数,
        材料.受け.遠方環境,
    ));
    グラフ.パスを積む(copy_pass::立方体の読み戻しを作る(
        "拡散照度読み戻し",
        拡散照度,
        vec![材料.拡散照度の範囲],
        材料.層数,
        材料.受け.拡散照度,
    ));
    グラフ.パスを積む(copy_pass::立方体の読み戻しを作る(
        "鏡面畳込み読み戻し",
        鏡面畳込み,
        材料.鏡面畳込みの段ごとの範囲.clone(),
        材料.層数,
        材料.受け.鏡面畳込み,
    ));
    グラフ.パスを積む(copy_pass::表の読み戻しを作る(
        反射率積分表,
        材料.反射率積分表の範囲,
        材料.受け.反射率積分表,
    ));
    graph::実行する(材料.device, 材料.command_buffer, グラフ, None);
}

/// 初期状態は大気のベイク済み画像を焼く画像と同じであり、レイアウトはUNDEFINEDである。
/// この記録が4つの画像すべての全テクセルを書き直すため、前の中身を捨ててよい。
fn 画像を登録する<'a>(
    グラフ: &mut graph::グラフ<'a>,
    画像: vk::Image,
    ビュー: vk::ImageView,
    寸法: vk::Extent2D,
) -> graph::画像ハンドル {
    グラフ.画像を登録する(
        画像,
        ビュー,
        graph::画像アスペクト::カラー,
        graph::焼いた画像を焼き直すときの初期状態(),
        寸法,
    )
}
