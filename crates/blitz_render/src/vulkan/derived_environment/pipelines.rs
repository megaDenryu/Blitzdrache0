//! 派生表現の3本のコンピュートパイプラインをまとめて生成し、まとめて破棄する組。触れる状態はこの3本だけであり、
//! 不変条件は「3本がそろって存在するか1本も存在しないかのどちらかである」ことである。
//!
//! 鏡面畳込みだけが即時定数の枠を持つのは、粗さを段ごとに押し込むためである。押し込むものが無いパイプラインへ
//! バイト数0の枠を宣言しないのは、0の範囲をvalidationが値域外として指摘するためである。

use super::descriptors::派生表現のディスクリプタ三点;
use super::inputs::粗さの即時定数のバイト数;
use crate::compute_shader::コンピュートシェーダー;
use crate::error::レンダラーエラー;
use crate::vulkan::allocator::GPU資源の確保係;
use crate::vulkan::atmosphere_lut::pipeline::{即時定数の枠, 生成パイプライン};

/// 3本のシェーダーの借用。所有はしないため、一式より長く生きる呼び出し元が持つ。
pub(in crate::vulkan) struct 派生表現のシェーダー一式<'a> {
    pub(in crate::vulkan) 拡散照度: &'a コンピュートシェーダー,
    pub(in crate::vulkan) 鏡面畳込み: &'a コンピュートシェーダー,
    pub(in crate::vulkan) 反射率積分表: &'a コンピュートシェーダー,
}

pub(super) struct 派生表現のパイプライン三点 {
    pub(super) 拡散照度: 生成パイプライン,
    pub(super) 鏡面畳込み: 生成パイプライン,
    pub(super) 反射率積分表: 生成パイプライン,
}

impl 派生表現のパイプライン三点 {
    pub(super) fn 生成する(
        確保係: &GPU資源の確保係<'_>,
        ディスクリプタ: &派生表現のディスクリプタ三点,
        シェーダー: &派生表現のシェーダー一式<'_>,
    ) -> Result<Self, レンダラーエラー> {
        let device = 確保係.論理デバイス();
        let 拡散照度 = 生成パイプライン::生成する(
            確保係,
            ディスクリプタ.拡散照度.レイアウトのハンドル(),
            即時定数の枠::無し,
            シェーダー.拡散照度.コード(),
        )?;
        let 鏡面畳込み = match 生成パイプライン::生成する(
            確保係,
            ディスクリプタ.鏡面畳込み.レイアウトのハンドル(),
            即時定数の枠::バイト数(粗さの即時定数のバイト数),
            シェーダー.鏡面畳込み.コード(),
        ) {
            Ok(パイプライン) => パイプライン,
            Err(誤り) => {
                拡散照度.破棄する(device);
                return Err(誤り);
            }
        };
        let 表 = 生成パイプライン::生成する(
            確保係,
            ディスクリプタ.反射率積分表.レイアウトのハンドル(),
            即時定数の枠::無し,
            シェーダー.反射率積分表.コード(),
        );
        match 表 {
            Ok(反射率積分表) => Ok(Self {
                拡散照度,
                鏡面畳込み,
                反射率積分表,
            }),
            Err(誤り) => {
                鏡面畳込み.破棄する(device);
                拡散照度.破棄する(device);
                Err(誤り)
            }
        }
    }

    pub(super) fn 破棄する(&self, device: &ash::Device) {
        self.反射率積分表.破棄する(device);
        self.鏡面畳込み.破棄する(device);
        self.拡散照度.破棄する(device);
    }
}
