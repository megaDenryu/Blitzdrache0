//! 派生表現の3つのディスクリプタをまとめて生成し、まとめて破棄する組。触れる状態はこの3つだけであり、
//! 不変条件は「3つがそろって存在するか1つも存在しないかのどちらかである」ことである。
//!
//! 鏡面畳込みのセットが最詳細段を含まないのは、その段を計算でなく遠方環境からの複製で作るためである。
//! セットの並びは段番号から1を引いた順であり、段2の書き込み先が添字1に当たる。

use ash::vk;

use super::descriptor::派生表現ディスクリプタ;
use super::images::派生表現の画像三点;
use super::table_descriptor::反射率積分表ディスクリプタ;
use crate::error::レンダラーエラー;

pub(super) struct 派生表現のディスクリプタ三点 {
    pub(super) 拡散照度: 派生表現ディスクリプタ,
    pub(super) 鏡面畳込み: 派生表現ディスクリプタ,
    pub(super) 反射率積分表: 反射率積分表ディスクリプタ,
}

impl 派生表現のディスクリプタ三点 {
    pub(super) fn 生成する(
        device: &ash::Device,
        遠方環境の配列ビュー: vk::ImageView,
        画像: &派生表現の画像三点,
    ) -> Result<Self, レンダラーエラー> {
        let 拡散照度 = 派生表現ディスクリプタ::生成する(device, 遠方環境の配列ビュー, &画像.拡散照度.段ごとの配列ビュー)?;
        let Some(計算で焼く段の書き込み先) = 画像.鏡面畳込み.段ごとの配列ビュー.get(1..) else {
            panic!("鏡面畳込みの画像が段を1つしか持たない(解像度の値域検証が破れている)");
        };
        let 鏡面畳込み = match 派生表現ディスクリプタ::生成する(device, 遠方環境の配列ビュー, 計算で焼く段の書き込み先)
        {
            Ok(ディスクリプタ) => ディスクリプタ,
            Err(誤り) => {
                拡散照度.破棄する(device);
                return Err(誤り);
            }
        };
        match 反射率積分表ディスクリプタ::生成する(device, 画像.反射率積分表.ビュー) {
            Ok(反射率積分表) => Ok(Self {
                拡散照度,
                鏡面畳込み,
                反射率積分表,
            }),
            Err(誤り) => {
                鏡面畳込み.破棄する(device);
                拡散照度.破棄する(device);
                Err(誤り)
            }
        }
    }

    pub(super) fn 破棄する(&self, device: &ash::Device) {
        self.反射率積分表.破棄する(device);
        self.鏡面畳込み.破棄する(device);
        self.拡散照度.破棄する(device);
    }
}
