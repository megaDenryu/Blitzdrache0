//! 束の登録が取引として成り立つための土台の検査。担当するのは、本番の登録が使う検査専用供給元が、
//! GPU資源を作る本番の供給元と同じ判定を返すことと、登録簿の取り外しと戻しが元の状態へ復元することを固定することである。
//!
//! この2つがあるから、束を足した呼び出しの`Ok`は「この束の材質は必ず世代へ積める」を意味し、
//! 差し替えが途中で落ちても登録簿を差し替え前へ戻せる
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段4bの補遺)。

#![allow(clippy::unwrap_used, clippy::expect_used)]

use crate::descriptor_indexing_limits::ディスクリプタ索引上限;
use crate::error::{レンダラーエラー, 材質資源表エラー};
use crate::texture_material::テクスチャ用途;
use crate::vulkan::material_table::capacity::テクスチャ表レイアウト容量;
use crate::vulkan::material_table::dry_run::検査専用供給元;
use crate::vulkan::material_table::frame_hold::フレーム保持状況;
use crate::vulkan::material_table::generation_build::構築する;
use crate::vulkan::material_table::generation_id::資源表世代ID;
use crate::vulkan::material_table::pack_input::梱包対象材質;
use crate::vulkan::material_table::stage_reserve::画素段の予約枠;
use crate::vulkan::sync::フレームスロット添字;

use super::fixture::検査用供給元;
use super::material_fixture::{検査用素材, 画像を選んだ材質};

/// 正準フォールバック3枚に加えてテクスチャ1枚だけが入る容量。2枚目の固有テクスチャで超過する。
fn 四枚の容量() -> テクスチャ表レイアウト容量 {
    let 上限 = ディスクリプタ索引上限::生成する(100, 100, 100);
    テクスチャ表レイアウト容量::決める(上限, 画素段の予約枠::現行のシーン画素段(), 4).unwrap()
}

fn 資源を作らずに試す(
    材質一覧: &[梱包対象材質<'_>], 容量: テクスチャ表レイアウト容量
) -> Result<(), レンダラーエラー> {
    構築する(&mut 検査専用供給元, 資源表世代ID::最初(), 容量, 材質一覧).map(|_| ())
}

/// 容量ちょうどは通り、1枚超えると型付きの失敗になる。本番の登録はこの判定を束を足した呼び出しの中で行うため、
/// 容量超過が次の描画まで遅れて同じ失敗を繰り返すことがない。
#[test]
fn 検査専用供給元は容量超過を資源を作る前に返す() {
    let 容量 = 四枚の容量();
    let 素材 = 検査用素材(テクスチャ用途::色);
    let 別素材 = 検査用素材(テクスチャ用途::線形データ);
    assert!(
        資源を作らずに試す(&[画像を選んだ材質(1, 1, 1, &素材)], 容量).is_ok(),
        "容量ちょうどは通る"
    );

    let 超える一覧 = [画像を選んだ材質(1, 1, 1, &素材), 画像を選んだ材質(2, 2, 2, &別素材)];
    let 誤り = 資源を作らずに試す(&超える一覧, 容量).expect_err("容量を1枚超える組は型付きの失敗になる");
    assert!(matches!(
        誤り,
        レンダラーエラー::材質資源表不正(材質資源表エラー::レイアウト容量超過 {
            常駐枚数: 5,
            レイアウト容量: 4
        })
    ));
}

/// 検査専用供給元の判定が、GPU資源を作る側と同じ材質の組で同じ結果になる。判定が食い違うと、
/// 試しに通った組が本番で落ちて、束を足した呼び出しの`Ok`が意味を失う。
#[test]
fn 検査専用供給元と資源を作る供給元の判定が一致する() {
    let 容量 = 四枚の容量();
    let 素材 = 検査用素材(テクスチャ用途::色);
    let 別素材 = 検査用素材(テクスチャ用途::線形データ);
    for 材質一覧 in [
        vec![画像を選んだ材質(1, 1, 1, &素材)],
        vec![画像を選んだ材質(1, 1, 1, &素材), 画像を選んだ材質(2, 2, 2, &別素材)],
    ] {
        let 試しの結果 = 資源を作らずに試す(&材質一覧, 容量).is_ok();
        let mut 供給元 = 検査用供給元::常に成功する();
        let 本番の結果 = 構築する(&mut 供給元, 資源表世代ID::最初(), 容量, &材質一覧).is_ok();
        assert_eq!(試しの結果, 本番の結果, "材質{}件で判定が食い違った", 材質一覧.len());
    }
}

/// 送信へ到達しなかったフレームが世代を保持したままにならないことの土台。束縛先を借りるだけでは保持状況が変わらず、
/// 同じスロットが次のフレームで改めて保持を記録できる。借りた時点で記録すると、この2度目が呼び出し順の誤りとして落ちる。
#[test]
fn 束縛先を借りるだけでは保持状況が変わらない() {
    let mut 状況 = フレーム保持状況::新規();
    let 世代 = 資源表世代ID::最初();
    let スロット = フレームスロット添字::先頭();
    assert!(!状況.保持しているか(世代), "借りる前は誰も保持していない");
    // 借りる操作は保持状況へ触れないため、ここでは何も起きない。
    assert!(!状況.保持しているか(世代), "借りただけでは保持しない");
    状況.束縛を記録する(スロット, 世代);
    assert!(状況.保持しているか(世代));
    状況.通過を記録する(スロット);
    状況.束縛を記録する(スロット, 世代);
    assert!(状況.保持しているか(世代), "通過を記録した後は同じスロットが再び保持できる");
}
