//! 世代台帳の状態遷移の検査。段4aの(i)進行中フレームのフェンス通過後にだけ1回退役すること、
//! (iii)材質レコードと画像集合を1つの世代として原子的に公開すること、(v)世代番号の枯渇を型付きの失敗にすること、
//! フェンス通過を記録していないスロットへの再束縛を通さないことを固定する。

#![allow(clippy::unwrap_used)]

use crate::error::材質資源表エラー;
use crate::texture_material::テクスチャ用途;
use crate::vulkan::material_table::generation_build::構築する;
use crate::vulkan::material_table::generation_id::資源表世代ID;
use crate::vulkan::material_table::ledger::資源表世代台帳;
use crate::vulkan::material_table::material_id::大域材質ID;
use crate::vulkan::sync::フレームスロット添字;

use super::fixture::検査用供給元;
use super::material_fixture::{余裕のあるレイアウト容量, 材質を作る, 検査用素材};

#[test]
fn 両フェンスの通過後にだけ旧世代が1回退役する() {
    let mut 供給元 = 検査用供給元::常に成功する();
    let 世代1 = 構築する(&mut 供給元, 資源表世代ID::最初(), 余裕のあるレイアウト容量(), &[]).unwrap();
    let mut 台帳 = 資源表世代台帳::最初の世代を公開する(世代1);
    let [スロット0, スロット1] = フレームスロット添字::全スロット();

    台帳.フレームが束縛する(スロット0);
    台帳.フレームが束縛する(スロット1);
    let 世代2 = 構築する(&mut 供給元, 台帳.次の世代idを発行する().unwrap(), 余裕のあるレイアウト容量(), &[]).unwrap();
    台帳.公開する(世代2);

    assert_eq!(台帳.退役した世代を回収する().len(), 0, "両スロットが保持している間は退役しない");
    台帳.フェンス通過を記録する(スロット0);
    assert_eq!(台帳.退役した世代を回収する().len(), 0, "片方が保持している間も退役しない");
    台帳.フェンス通過を記録する(スロット1);
    let 回収 = 台帳.退役した世代を回収する();
    assert_eq!(回収.len(), 1);
    assert_eq!(回収[0].世代id().番号(), 資源表世代ID::最初().番号());
    assert_eq!(台帳.退役待ち件数(), 0);
    assert_eq!(台帳.退役した世代を回収する().len(), 0, "同じ世代を2回退役させない");
}

#[test]
fn 材質レコードと画像集合を1つの世代として同時に差し替える() {
    let 素材 = 検査用素材(テクスチャ用途::色);
    let mut 供給元 = 検査用供給元::常に成功する();
    let 世代1 = 構築する(&mut 供給元, 資源表世代ID::最初(), 余裕のあるレイアウト容量(), &[材質を作る(1, None)]).unwrap();
    let mut 台帳 = 資源表世代台帳::最初の世代を公開する(世代1);
    assert_eq!(台帳.公開中().材質件数(), 1);
    assert_eq!(
        台帳.公開中().画像枚数(),
        3,
        "材質がテクスチャを持たない世代は正準フォールバックだけを持つ"
    );

    let 世代2 = 構築する(
        &mut 供給元,
        台帳.次の世代idを発行する().unwrap(),
        余裕のあるレイアウト容量(),
        &[材質を作る(1, Some(&素材)), 材質を作る(2, None)],
    )
    .unwrap();
    台帳.公開する(世代2);

    assert_eq!(台帳.公開中().材質件数(), 2);
    assert_eq!(台帳.公開中().画像枚数(), 4);
    assert!(台帳.公開中().解決する(大域材質ID::生成する(2)).is_ok());
    assert_eq!(台帳.退役待ち件数(), 1, "旧世代は公開から降りても退役待ちに残る");
}

#[test]
fn 世代番号の枯渇を型付きの失敗にする() {
    let mut 供給元 = 検査用供給元::常に成功する();
    let 末尾世代 = 構築する(&mut 供給元, 資源表世代ID::番号から生成する(u32::MAX), 余裕のあるレイアウト容量(), &[]).unwrap();
    let mut 台帳 = 資源表世代台帳::最初の世代を公開する(末尾世代);
    assert_eq!(台帳.次の世代idを発行する().unwrap_err(), 材質資源表エラー::世代番号の枯渇);
}

#[test]
#[should_panic(expected = "フェンス通過を記録していないスロット")]
fn フェンス通過なしの再束縛を通さない() {
    let mut 供給元 = 検査用供給元::常に成功する();
    let 世代1 = 構築する(&mut 供給元, 資源表世代ID::最初(), 余裕のあるレイアウト容量(), &[]).unwrap();
    let mut 台帳 = 資源表世代台帳::最初の世代を公開する(世代1);
    let [スロット0, _] = フレームスロット添字::全スロット();
    台帳.フレームが束縛する(スロット0);
    let 発行id = 台帳.次の世代idを発行する().unwrap();
    台帳.公開する(構築する(&mut 供給元, 発行id, 余裕のあるレイアウト容量(), &[]).unwrap());
    // このスロットはまだフェンス通過を記録していないため、旧世代の保持を消してはならない。
    台帳.フレームが束縛する(スロット0);
}
