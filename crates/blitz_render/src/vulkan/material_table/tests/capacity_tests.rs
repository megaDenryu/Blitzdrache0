//! 容量の検査。段4aの(v)容量超過を型付きの失敗にすること、そして超過の判定がディスクリプタを1つも作る前に返ることを固定する。
//! 予算のちょうど手前・ちょうど・1枚超過の3点を見るのは、上限の引き算の境界を1枚ずれた実装が通り抜けないためである。

#![allow(clippy::unwrap_used)]

use crate::descriptor_indexing_limits::ディスクリプタ索引上限;
use crate::error::{レンダラーエラー, 材質資源表エラー};
use crate::texture_material::テクスチャ用途;
use crate::vulkan::material_table::capacity::テクスチャ表容量;
use crate::vulkan::material_table::generation_build::構築する;
use crate::vulkan::material_table::generation_id::資源表世代ID;
use crate::vulkan::material_table::stage_reserve::画素段の予約枠;

use super::fixture::{検査用供給元, 検査用素材, 画像を選んだ材質};

/// 画像ディスクリプタの上限10・資源合計の上限20。現行のシーン画素段の予約枠(画像1・バッファ4・色添付1)を引くと予算は9枚になる。
fn 予算が9枚になる上限() -> ディスクリプタ索引上限 {
    ディスクリプタ索引上限::生成する(10, 10, 20)
}

#[test]
fn 予算の境界の前後で容量の可否が切り替わる() {
    let 予約枠 = 画素段の予約枠::現行のシーン画素段();
    assert_eq!(テクスチャ表容量::決める(予算が9枚になる上限(), 予約枠, 8).unwrap().枚数(), 8);
    assert_eq!(テクスチャ表容量::決める(予算が9枚になる上限(), 予約枠, 9).unwrap().枚数(), 9);
    assert_eq!(
        テクスチャ表容量::決める(予算が9枚になる上限(), 予約枠, 10).unwrap_err(),
        材質資源表エラー::容量超過 {
            必要枚数: 10, 予算枚数: 9
        }
    );
}

#[test]
fn 予約枠が上限を食い尽くす機材を予算不足として拒む() {
    let 予約枠 = 画素段の予約枠::内訳から生成する(1, 4, 1);
    assert_eq!(
        テクスチャ表容量::決める(ディスクリプタ索引上限::生成する(1, 10, 20), 予約枠, 1).unwrap_err(),
        材質資源表エラー::予算不足 { 予約枚数: 1, 上限: 1 }
    );
}

#[test]
fn 容量超過はディスクリプタを1つも作る前に返る() {
    let 素材 = 検査用素材(テクスチャ用途::色);
    let mut 供給元 = 検査用供給元::常に成功する();
    // 予約枠を差し引いた予算が3枚の機材へ、正準フォールバック3枚と材質テクスチャ1枚の計4枚を求める。
    let 上限 = ディスクリプタ索引上限::生成する(4, 10, 20);
    let 材質一覧 = [画像を選んだ材質(1, 1, 1, &素材)];
    let 結果 = 構築する(&mut 供給元, 資源表世代ID::最初(), 上限, 画素段の予約枠::現行のシーン画素段(), &材質一覧);
    assert!(matches!(
        結果,
        Err(レンダラーエラー::材質資源表不正(材質資源表エラー::容量超過 {
            必要枚数: 4,
            予算枚数: 3
        }))
    ));
    assert_eq!(供給元.生存枚数(), 0);
    assert_eq!(供給元.退役枚数(), 0, "容量の判定は画像を1枚も作る前に行う");
}
