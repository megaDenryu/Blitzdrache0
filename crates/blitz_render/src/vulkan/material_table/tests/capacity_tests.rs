//! 容量の検査。レイアウト容量が要素数どおりに決まり予算不足を型付きの失敗にすること、世代の常駐枚数が
//! レイアウト容量へ収まることをディスクリプタを1つも作る前に確かめることを固定する。
//! 容量より1枚少ない・ちょうど・1枚多いの3点を見るのは、引き算と比較の境界を1枚ずれた実装が通り抜けないためである。

#![allow(clippy::unwrap_used)]

use crate::descriptor_indexing_limits::ディスクリプタ索引上限;
use crate::error::{レンダラーエラー, 材質資源表エラー};
use crate::texture_material::テクスチャ用途;
use crate::vulkan::material_table::capacity::テクスチャ表レイアウト容量;
use crate::vulkan::material_table::generation_build::資源表世代を構築する;
use crate::vulkan::material_table::generation_id::資源表世代ID;
use crate::vulkan::material_table::stage_reserve::画素段の予約枠;

use super::fixture::検査用供給元;
use super::material_fixture::{検査用素材, 画像を選んだ材質};

/// 画像ディスクリプタの上限10・資源合計の上限20。現行のシーン画素段の予約枠(画像1・バッファ4・サンプラー1・色添付1)を
/// 引くと、画像の上限からの残り9枚が最も厳しく、予算は9枚になる。
fn 予算が9枚になる上限() -> ディスクリプタ索引上限 {
    ディスクリプタ索引上限::生成する(10, 10, 20)
}

fn 容量を決める(
    上限: ディスクリプタ索引上限, 要素数: u32
) -> Result<テクスチャ表レイアウト容量, 材質資源表エラー> {
    テクスチャ表レイアウト容量::決める(上限, 画素段の予約枠::現行のシーン画素段(), 要素数)
}

/// 要素数を予算で切り下げないのは、シェーダーの配列の宣言と同じ数でなければならないためである。
#[test]
fn レイアウト容量は要素数どおりに決まり予算が足りなければ失敗する() {
    assert_eq!(
        容量を決める(予算が9枚になる上限(), 8).unwrap().枚数(),
        8,
        "予算に収まる要素数はそのまま通る"
    );
    assert_eq!(容量を決める(予算が9枚になる上限(), 9).unwrap().枚数(), 9, "予算ちょうどの要素数は通る");
    assert_eq!(
        容量を決める(予算が9枚になる上限(), 10).unwrap_err(),
        材質資源表エラー::レイアウト容量超過 {
            常駐枚数: 10,
            レイアウト容量: 9
        },
        "予算を1枚超える要素数は型付きの失敗になる"
    );
}

#[test]
fn 予約枠が上限を食い尽くす機材を予算不足として拒む() {
    assert_eq!(
        容量を決める(ディスクリプタ索引上限::生成する(1, 10, 20), 1).unwrap_err(),
        材質資源表エラー::予算不足 { 予約枚数: 1, 上限: 1 }
    );
}

#[test]
fn 常駐枚数がレイアウト容量より1枚少なければ公開できる() {
    let mut 供給元 = 検査用供給元::常に成功する();
    // 正準フォールバック3枚だけで、レイアウト容量4枚より1枚少ない。
    let 容量 = 容量を決める(予算が9枚になる上限(), 4).unwrap();
    let 世代 = 資源表世代を構築する(&mut 供給元, 資源表世代ID::最初(), 容量, &[]).unwrap();
    assert_eq!(世代.画像枚数(), 3);
    assert_eq!(供給元.生存枚数(), 3);
}

#[test]
fn 常駐枚数がレイアウト容量ちょうどなら公開できる() {
    let 素材 = 検査用素材(テクスチャ用途::色);
    let mut 供給元 = 検査用供給元::常に成功する();
    // 正準フォールバック3枚と材質テクスチャ1枚で、レイアウト容量4枚とちょうど並ぶ。
    let 容量 = 容量を決める(予算が9枚になる上限(), 4).unwrap();
    let 世代 = 資源表世代を構築する(&mut 供給元, 資源表世代ID::最初(), 容量, &[画像を選んだ材質(1, 1, 1, &素材)]).unwrap();
    assert_eq!(世代.画像枚数(), 4);
    assert_eq!(供給元.生存枚数(), 4);
}

#[test]
fn レイアウト容量の超過はディスクリプタを1つも作る前に返る() {
    let 素材 = 検査用素材(テクスチャ用途::色);
    let mut 供給元 = 検査用供給元::常に成功する();
    let 容量 = 容量を決める(予算が9枚になる上限(), 3).unwrap();
    let 結果 = 資源表世代を構築する(&mut 供給元, 資源表世代ID::最初(), 容量, &[画像を選んだ材質(1, 1, 1, &素材)]);
    assert!(matches!(
        結果,
        Err(レンダラーエラー::材質資源表不正(材質資源表エラー::レイアウト容量超過 {
            常駐枚数: 4,
            レイアウト容量: 3
        }))
    ));
    assert_eq!(供給元.生存枚数(), 0);
    assert_eq!(供給元.退役枚数(), 0, "常駐枚数の判定は画像を1枚も作る前に行う");
}
