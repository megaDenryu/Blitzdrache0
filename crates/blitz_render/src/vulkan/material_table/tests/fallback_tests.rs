//! 正準フォールバックの検査。段4aの(vi)用途型からスロットへの解決が梱包工程に閉じ、予約添字を約束せずに
//! 全スロットが実在する画像を指すことを固定する。

#![allow(clippy::unwrap_used)]

use crate::texture_material::テクスチャ用途;
use crate::vulkan::material_table::generation::資源表世代;
use crate::vulkan::material_table::generation_build::資源表世代を構築する;
use crate::vulkan::material_table::generation_id::資源表世代ID;
use crate::vulkan::material_table::generation_record::世代内材質レコード;
use crate::vulkan::material_table::material_id::大域材質ID;
use crate::vulkan::material_table::texture_role::材質テクスチャ役割;

use super::fixture::検査用供給元;
use super::material_fixture::{余裕のあるレイアウト容量, 材質を作る, 検査用素材};

fn レコードを引く<画像, 付属>(世代: &資源表世代<画像, 付属>, 番号: u64) -> &世代内材質レコード {
    let 参照 = 世代.解決する(大域材質ID::生成する(番号)).unwrap();
    let 添字 = 世代.描画へ渡す解決(参照).unwrap().レコード添字();
    世代.レコード(添字).unwrap()
}

fn 役割別スロット(レコード: &世代内材質レコード) -> Vec<u32> {
    材質テクスチャ役割::全役割.iter().map(|役割| レコード.スロット(*役割).添字()).collect()
}

#[test]
fn テクスチャ無しの材質は用途ごとの実在スロットを指し特徴ビットが立たない() {
    let mut 供給元 = 検査用供給元::常に成功する();
    let 材質一覧 = [材質を作る(1, None), 材質を作る(2, None)];
    let 世代 = 資源表世代を構築する(&mut 供給元, 資源表世代ID::最初(), 余裕のあるレイアウト容量(), &材質一覧).unwrap();

    let レコード = レコードを引く(&世代, 1);
    let 画像枚数 = u32::try_from(世代.画像枚数()).unwrap();
    for 役割 in 材質テクスチャ役割::全役割 {
        assert!(!レコード.特徴集合().役割を持つか(役割), "テクスチャ無しの役割のビットは立たない");
        assert!(レコード.スロット(役割).添字() < 画像枚数, "無しの役割も実在する画像を指す");
    }
    assert_eq!(レコード.特徴集合().生値(), 0);
    let mut 重複除去 = 役割別スロット(レコード);
    重複除去.sort_unstable();
    重複除去.dedup();
    assert_eq!(重複除去.len(), 3, "用途ごとに別の既定テクスチャを指す");
    assert_eq!(
        役割別スロット(レコード),
        役割別スロット(レコードを引く(&世代, 2)),
        "同じ世代の中では用途ごとのフォールバックは1つに定まる"
    );
}

#[test]
fn テクスチャ有りの役割だけビットが立ちフォールバックと違うスロットを指す() {
    let 素材 = 検査用素材(テクスチャ用途::色);
    let mut 供給元 = 検査用供給元::常に成功する();
    let 材質一覧 = [材質を作る(1, Some(&素材)), 材質を作る(2, None)];
    let 世代 = 資源表世代を構築する(&mut 供給元, 資源表世代ID::最初(), 余裕のあるレイアウト容量(), &材質一覧).unwrap();

    let テクスチャ有り = レコードを引く(&世代, 1);
    let テクスチャ無し = レコードを引く(&世代, 2);
    assert!(テクスチャ有り.特徴集合().役割を持つか(材質テクスチャ役割::ベースカラー));
    assert!(!テクスチャ有り.特徴集合().役割を持つか(材質テクスチャ役割::法線マップ));
    assert_ne!(
        テクスチャ有り.スロット(材質テクスチャ役割::ベースカラー),
        テクスチャ無し.スロット(材質テクスチャ役割::ベースカラー)
    );
    assert_eq!(
        テクスチャ有り.スロット(材質テクスチャ役割::法線マップ),
        テクスチャ無し.スロット(材質テクスチャ役割::法線マップ)
    );
}
