//! アセットの差し替えで世代が切り替わるときの、旧世代と新世代の混ざらなさの検査。
//!
//! 固定するのは2つである。同じ大域材質IDが世代ごとに別の係数を返すこと。旧世代で解決した材質GPU参照を
//! 新世代が受け取らないこと。前者は「旧いフレームが旧い画素を、新しいフレームが新しい画素を出す」の
//! CPU側の全体であり、後者は「1つの発行が旧い表を束縛したまま新しいレコードを読む」経路が存在しないことである。
//! フレームの保持と退役の順序そのものは`ledger_tests`が持つ(参照: `_doc/設計/GPU資源束縛の分離と索引化.md`
//! 「段階導入」の段4bの検収ゲート(iv))。

#![allow(clippy::unwrap_used, clippy::expect_used)]

use crate::error::材質資源表エラー;
use crate::vulkan::material_table::generation::資源表世代;
use crate::vulkan::material_table::generation_build::資源表世代を構築する;
use crate::vulkan::material_table::generation_id::資源表世代ID;
use crate::vulkan::material_table::material_id::大域材質ID;
use crate::vulkan::material_table::pack_input::梱包対象材質;
use crate::vulkan::material_variant::シェーディングモデル種別;

use super::fixture::検査用供給元;
use super::material_fixture::余裕のあるレイアウト容量;

/// 差し替えの前後で変わるのはベースカラー係数の赤成分だけである。同じ材質IDが世代で別の値を返すことだけを見たいためである。
fn 赤の材質(赤: f32) -> 梱包対象材質<'static> {
    梱包対象材質::生成する(
        大域材質ID::生成する(1),
        シェーディングモデル種別::標準金属粗さPBR,
        [赤, 0.0, 0.0, 1.0],
        0.0,
        1.0,
        [None, None, None],
    )
}

type 検査用世代 = 資源表世代<u32, ()>;

fn 世代を作る(供給元: &mut 検査用供給元, 番号: u32, 赤: f32) -> 検査用世代 {
    let 世代id = if 番号 == 1 {
        資源表世代ID::最初()
    } else {
        資源表世代ID::最初().次を作る().unwrap()
    };
    資源表世代を構築する(供給元, 世代id, 余裕のあるレイアウト容量(), &[赤の材質(赤)]).unwrap()
}

fn 赤成分を読む(世代: &検査用世代) -> f32 {
    let 参照 = 世代.解決する(大域材質ID::生成する(1)).unwrap();
    let 添字 = 世代.描画へ渡す解決(参照).unwrap().レコード添字();
    世代.レコード(添字).expect("解決した添字はその世代のレコードを指す").ベースカラー係数()[0]
}

/// 旧世代と新世代が同時に生きている間、同じ材質IDはそれぞれの世代の係数を返す。
/// どちらかが他方の値を返すと、旧いフレームと新しいフレームの画素が混ざる。
#[test]
fn 同じ材質idが世代ごとに自分の係数を返す() {
    let mut 供給元 = 検査用供給元::常に成功する();
    let 旧世代 = 世代を作る(&mut 供給元, 1, 0.25);
    let 新世代 = 世代を作る(&mut 供給元, 2, 0.75);
    assert_eq!(赤成分を読む(&旧世代), 0.25, "旧世代は差し替え前の係数を返す");
    assert_eq!(赤成分を読む(&新世代), 0.75, "新世代は差し替え後の係数を返す");
}

/// 旧世代で解決した参照を新世代へ渡すと型付きの失敗になる。束縛した表と別の世代の添字が描画定数へ載る経路が無い。
#[test]
fn 旧世代で解決した参照を新世代は受け取らない() {
    let mut 供給元 = 検査用供給元::常に成功する();
    let 旧世代 = 世代を作る(&mut 供給元, 1, 0.25);
    let 新世代 = 世代を作る(&mut 供給元, 2, 0.75);
    let 旧参照 = 旧世代.解決する(大域材質ID::生成する(1)).unwrap();
    let 誤り = 新世代.描画へ渡す解決(旧参照).expect_err("旧世代の参照は新世代では通らない");
    assert!(matches!(
        誤り,
        材質資源表エラー::異世代の混在 {
            参照の世代: 1,
            束縛する世代: 2
        }
    ));
}
