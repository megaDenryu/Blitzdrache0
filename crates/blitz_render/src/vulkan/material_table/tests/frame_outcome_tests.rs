//! フレームの結末が資源表世代の寿命へ及ぼす影響の検査。担当するのは、そのフレームがキューへの送信に到達したかどうかで
//! 保持の記録が分かれ、旧世代が退役できる時期が変わることを固定することである。
//!
//! 本番の呼び出し元は`renderer/draw_dispatch.rs`の`現在の画像で描画する`である。送信へ到達しなかったフレームは保持を
//! 記録せず、送信が成ったフレームは提示で失敗しても保持を記録する。ここでは2つの経路が台帳へ残す状態を並べて見る。
//! 参照: `crates/blitz_render/src/vulkan/frame/submit_outcome.rs`

#![allow(clippy::unwrap_used)]

use crate::vulkan::material_table::generation::資源表世代;
use crate::vulkan::material_table::generation_build::構築する;
use crate::vulkan::material_table::generation_id::資源表世代ID;
use crate::vulkan::material_table::ledger::資源表世代台帳;
use crate::vulkan::sync::フレームスロット添字;

use super::fixture::検査用供給元;
use super::material_fixture::余裕のあるレイアウト容量;

fn 世代を1つ公開した台帳(供給元: &mut 検査用供給元) -> 資源表世代台帳<u32, ()> {
    let 初期世代: 資源表世代<u32, ()> = 構築する(供給元, 資源表世代ID::最初(), 余裕のあるレイアウト容量(), &[]).unwrap();
    資源表世代台帳::最初の世代を公開する(初期世代)
}

fn 次の世代を公開する(台帳: &mut 資源表世代台帳<u32, ()>, 供給元: &mut 検査用供給元) {
    let 発行id = 台帳.次の世代idを発行する().unwrap();
    台帳.公開する(構築する(供給元, 発行id, 余裕のあるレイアウト容量(), &[]).unwrap());
}

/// 世代の作り直しや記録の途中で失敗して送信へ到達しなかったフレームを表す。束縛先を借りただけで保持は記録しない。
#[test]
fn 送信へ到達しなかったフレームは世代を保持しない() {
    let mut 供給元 = 検査用供給元::常に成功する();
    let mut 台帳 = 世代を1つ公開した台帳(&mut 供給元);
    let スロット = フレームスロット添字::先頭();

    次の世代を公開する(&mut 台帳, &mut 供給元);
    assert_eq!(
        台帳.退役した世代を回収する().len(),
        1,
        "誰も保持していない旧世代は次の公開の直後に退役できる"
    );
    // 同じスロットを使う次のフレームは、フェンス通過を1度も記録しないまま束縛できる。前のフレームが保持を記録していれば
    // ここが呼び出し順の誤りとして落ち、失敗のたびにそのスロットが使えなくなる。
    台帳.フレームが束縛する(スロット);
}

/// 送信が成った後に読み戻しの待機か提示で失敗したフレームを表す。GPUは既に材質のセットを読むため保持を記録する。
#[test]
fn 送信の後で失敗したフレームも読み終えるまで世代を保持する() {
    let mut 供給元 = 検査用供給元::常に成功する();
    let mut 台帳 = 世代を1つ公開した台帳(&mut 供給元);
    let スロット = フレームスロット添字::先頭();

    台帳.フレームが束縛する(スロット);
    次の世代を公開する(&mut 台帳, &mut 供給元);
    assert_eq!(台帳.退役した世代を回収する().len(), 0, "送信が成ったフレームが読んでいる間は退役しない");
    台帳.フェンス通過を記録する(スロット);
    assert_eq!(台帳.退役した世代を回収する().len(), 1, "フェンス通過の後に1回だけ退役する");
}
