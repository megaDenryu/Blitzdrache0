//! 公開中の資源表世代と退役待ちの世代の所有者。担当するのは、世代番号の発番と、完全に構築済みの世代への原子的な差し替えである。
//! 進行中フレームの保持を見て退役を決める操作は`retirement`が持ち、この階層は所有と発番だけに触れる。
//!
//! 注意: 公開は差し替えであって書き換えではない。材質レコード列と画像集合は世代が1つの値として持つため、
//! 「レコードだけ新しく画像は古い」という中間状態がフレームから見えることはない。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「ディスクリプタ索引の採用範囲」

mod retirement;

use crate::error::材質資源表エラー;

use super::frame_hold::フレーム保持状況;
use super::generation::資源表世代;
use super::generation_id::資源表世代ID;

pub(crate) struct 資源表世代台帳<画像> {
    公開中: 資源表世代<画像>,
    /// 公開から降りたが、まだどれかのフレームが保持しているかもしれない世代。
    退役待ち: Vec<資源表世代<画像>>,
    保持状況: フレーム保持状況,
    直近に発行した世代id: 資源表世代ID,
}

impl<画像> 資源表世代台帳<画像> {
    pub(crate) fn 最初の世代を公開する(初期世代: 資源表世代<画像>) -> Self {
        let 直近に発行した世代id = 初期世代.世代id();
        Self {
            公開中: 初期世代,
            退役待ち: Vec::new(),
            保持状況: フレーム保持状況::新規(),
            直近に発行した世代id,
        }
    }

    pub(crate) fn 公開中(&self) -> &資源表世代<画像> {
        &self.公開中
    }

    /// 次に構築する世代の番号。構築が失敗しても番号は戻さない。戻すと、失敗した世代を束縛していないことの確認が
    /// 番号の一致では言えなくなる。
    pub(crate) fn 次の世代idを発行する(&mut self) -> Result<資源表世代ID, 材質資源表エラー> {
        let 次 = self.直近に発行した世代id.次を作る()?;
        self.直近に発行した世代id = 次;
        Ok(次)
    }

    /// 注意: 発行した番号で構築した世代だけを渡す。別の番号の世代を公開するのは呼び出し元のバグであり、
    /// 通すと退役待ちの世代と同じ番号の世代が並び、材質GPU参照の世代一致検査が別の表を通す。
    pub(crate) fn 公開する(&mut self, 世代: 資源表世代<画像>) {
        assert!(
            世代.世代id() == self.直近に発行した世代id,
            "発行していない資源表世代{}を公開しようとした(直近の発行は{})",
            世代.世代id().番号(),
            self.直近に発行した世代id.番号()
        );
        let 旧世代 = std::mem::replace(&mut self.公開中, 世代);
        self.退役待ち.push(旧世代);
    }

    /// 破棄の経路が使う、全世代の取り出し。前提: 呼び出し元がGPUの全作業完了を待ってから呼ぶ。
    pub(crate) fn 全世代を取り出す(&mut self) -> Vec<資源表世代<画像>> {
        let 置き換え = 資源表世代::空にする(self.公開中.世代id());
        let 公開中 = std::mem::replace(&mut self.公開中, 置き換え);
        let mut 一覧 = vec![公開中];
        一覧.append(&mut self.退役待ち);
        一覧
    }
}
