//! 確定していない材質の登録の受け渡し。担当するのは、下書きを始める前の状態へ完全に戻すための材料を1つの値として運ぶことと、
//! 「積む→GPU資源を作らずに構築を試す→通れば確定、落ちれば積んだぶんを外す」の順を1箇所へ閉じることである。
//!
//! 試してから確定するのは、容量超過や梱包の不整合のような決定的な失敗を、束を足した呼び出しがその場で`Err`として返すためである。
//! 試さずに積むと、失敗が次の描画まで遅れ、束を足した側は成功したと信じたまま以後の描画が毎回同じ失敗を返す。

use crate::draw_bundle_id::描画束ID;
use crate::error::レンダラーエラー;
use crate::render_object_material::描画対象素材;

use super::super::dry_run::検査専用供給元;
use super::super::generation_build;
use super::super::generation_id::資源表世代ID;
use super::super::registration::束の保持材質;
use super::{描画対象別の材質ID, 材質の登録状態};

/// 積んだが確定していない材質の登録。確定するまで世代の作り直しを予約せず、取り消しで下書き前の状態へ完全に戻す。
/// 運ぶのは3つである。積んだ束のID、同じ束IDの材質が既にあった場合の取り外した位置と中身、下書きを始めた時点の
/// 世代の作り直しの要否。位置まで持つのは、登録簿の並びが梱包の順であり、順が変わると同じ材質のレコード添字が変わるためである。
/// 注意: 下書きを持ったまま別の束を下書きしてはならない。取り消しが2つの下書きの順序を復元できない。
pub(crate) struct 材質登録の下書き {
    束id: 描画束ID,
    /// 同じ束IDの材質が既にあった場合の、取り外した位置と中身。
    預かった旧材質: Option<(usize, 束の保持材質)>,
    下書き前の作り直し要否: bool,
}

impl 材質の登録状態 {
    /// 束1つぶんの材質を下書きとして積む。返すのは描画対象ごと材質スロットごとの大域材質IDと、確定と取り消しに使う下書きである。
    /// 容量超過と梱包の不整合はここで確かめて`Err`にする。GPU資源を作る世代の作り直しは、呼び出し元が束のGPU資源まで
    /// 作り終えて`下書きを確定する`を呼んだときに初めて予約される。
    ///
    /// 同じ束IDの材質が既にあれば取り外して下書きに預かる。差し替えが途中で落ちたときに、取り外す前の並びと
    /// 作り直しの要否をそのまま戻せるようにするためである。
    pub(crate) fn 束の材質を下書きする(
        &mut self,
        束id: 描画束ID,
        描画対象一覧: &[描画対象素材],
    ) -> Result<(Vec<描画対象別の材質ID>, 材質登録の下書き), レンダラーエラー> {
        let 預かった旧材質 = self.登録簿.束を取り外す(束id);
        let 下書き = 材質登録の下書き {
            束id,
            預かった旧材質,
            下書き前の作り直し要否: self.世代の作り直しが要るか,
        };
        let 材質id一覧 = self.登録簿.束を登録する(束id, 描画対象一覧);
        match self.資源を作らずに構築を試す() {
            Ok(()) => Ok((材質id一覧, 下書き)),
            Err(誤り) => {
                self.下書きを取り消す(下書き);
                Err(誤り)
            }
        }
    }

    /// 下書きを確定し、登録簿の内容を世代へ反映し直すことを予約する。
    pub(crate) fn 下書きを確定する(&mut self, 下書き: 材質登録の下書き) {
        drop(下書き);
        self.世代の作り直しが要るか = true;
    }

    /// 下書きを捨てて、下書きを始める前の状態へ戻す。戻すのは登録簿の中身・並び・作り直しの要否の3つである。
    /// 並びまで戻すのは、並びが梱包の順であり、順が変わると同じ材質のレコード添字が変わるためである。
    pub(crate) fn 下書きを取り消す(&mut self, 下書き: 材質登録の下書き) {
        self.登録簿.束を解除する(下書き.束id);
        if let Some((位置, 保持)) = 下書き.預かった旧材質 {
            self.登録簿.束を位置へ戻す(位置, 下書き.束id, 保持);
        }
        self.世代の作り直しが要るか = 下書き.下書き前の作り直し要否;
    }

    /// 保持中の全材質でGPU資源を1つも作らずに世代の構築を通す。世代番号を発行しないのは、この試行が
    /// 公開へ進まないためである(発行すると、公開されない番号で未消費の発行が置き換わる)。
    fn 資源を作らずに構築を試す(&self) -> Result<(), レンダラーエラー> {
        let 材質一覧 = self.梱包対象を並べる();
        let mut 供給元 = 検査専用供給元;
        generation_build::構築する(&mut 供給元, 資源表世代ID::最初(), self.レイアウト容量, &材質一覧).map(|_| ())
    }
}
