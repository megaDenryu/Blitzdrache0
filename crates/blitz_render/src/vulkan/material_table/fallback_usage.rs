//! テクスチャを持たない材質でも束縛される、意味ごとの既定テクスチャの種類。担当するのは、種類から実在する1x1の画素データを作ることである。
//!
//! 注意: 「無し」を予約添字やマジック番号の番兵で表さない。どの世代でも全スロットは実在する画像を指し、
//! テクスチャの有無を表すのは材質特徴集合のビットだけである。ビットがfalseでもシェーダーが標本して構わない値を置く。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「材質レコードとテクスチャ台帳」

use crate::texture_material::{テクスチャ用途, テクスチャ素材};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 正準フォールバック用途 {
    白,                 // ベースカラーの標本へ掛けても色を変えない白。
    平坦法線,           // 接線空間の(0, 0, 1)を8ビットの符号なし正規化値へ写した、凹凸のない法線。
    中立金属粗さ,       // 金属度と粗さの係数をそのまま活かす1.0。glTFの規約どおり緑成分が粗さ、青成分が金属度である。
    先頭の層だけの重み, // 地表の層の重みを持たない材質が指す既定。先頭の層だけが満量であり、塗られていないチャンクの重みと同じ値である。
}

impl 正準フォールバック用途 {
    /// 用途ごとのスロットを並べる配列の並び順の正本。`配列添字`と同じ順に並べる。
    pub(crate) const 全用途: [Self; 4] = [Self::白, Self::平坦法線, Self::中立金属粗さ, Self::先頭の層だけの重み];

    pub(crate) const fn 配列添字(self) -> usize {
        match self {
            Self::白 => 0,
            Self::平坦法線 => 1,
            Self::中立金属粗さ => 2,
            Self::先頭の層だけの重み => 3,
        }
    }

    const fn 画素(self) -> [u8; 4] {
        match self {
            Self::白 | Self::中立金属粗さ => [255, 255, 255, 255],
            Self::平坦法線 => [128, 128, 255, 255],
            Self::先頭の層だけの重み => [255, 0, 0, 0],
        }
    }

    const fn ビュー契約(self) -> テクスチャ用途 {
        match self {
            Self::白 => テクスチャ用途::色,
            Self::平坦法線 | Self::中立金属粗さ | Self::先頭の層だけの重み => テクスチャ用途::線形データ,
        }
    }

    /// 1x1の画素1つぶんの素材。長さの検証に落ちるのは画素の定義を壊したときだけであり、回復できる失敗ではない。
    pub(crate) fn 素材を作る(self) -> テクスチャ素材 {
        テクスチャ素材::rgba8の原寸から生成する(1, 1, self.画素().to_vec(), self.ビュー契約())
            .unwrap_or_else(|誤り| panic!("正準フォールバックの1x1画素が長さの検証に落ちた: {誤り}"))
    }
}
