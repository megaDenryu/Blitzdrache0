//! 資源表世代を1つ作り上げる工程。受け取るのは供給元・世代番号・固定のレイアウト容量・材質一覧で、返すのは公開できる世代である。
//! 常駐枚数の確定・画像の常駐・梱包・完成検査をこの順で行う。
//!
//! 注意: 途中で失敗したら、その世代のために作った画像だけを退役させて何も返さない。公開中の世代へは触れないため、
//! 構築の失敗で表示中の絵が壊れない。常駐枚数の判定を最初に置くのは、ディスクリプタを1つも作る前に超過を返すためである。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」

mod completion_check;
mod residency;

use crate::error::レンダラーエラー;

use super::capacity::テクスチャ表レイアウト容量;
use super::fallback_usage::正準フォールバック用途;
use super::generation::資源表世代;
use super::generation_id::資源表世代ID;
use super::pack_input::梱包対象材質;
use super::packer;
use super::residency_count::世代の常駐枚数;
use super::supplier::常駐テクスチャ供給元;
use super::texture_registry::必要枚数を数える;

type 構築結果<供給元> =
    Result<資源表世代<<供給元 as 常駐テクスチャ供給元>::常駐画像, <供給元 as 常駐テクスチャ供給元>::世代付属資源>, レンダラーエラー>;

pub(crate) fn 構築する<供給元: 常駐テクスチャ供給元>(
    供給元: &mut 供給元,
    世代id: 資源表世代ID,
    レイアウト容量: テクスチャ表レイアウト容量,
    材質一覧: &[梱包対象材質<'_>],
) -> 構築結果<供給元> {
    let フォールバック枚数 =
        u32::try_from(正準フォールバック用途::全用途.len()).unwrap_or_else(|_| panic!("正準フォールバックの用途数がu32に収まらない"));
    let 必要枚数 = 必要枚数を数える(材質一覧, フォールバック枚数);
    let 常駐枚数 = 世代の常駐枚数::確かめる(必要枚数, レイアウト容量)?;

    let mut 画像集合 = Vec::new();
    let 結果 = residency::積む(供給元, &mut 画像集合, 常駐枚数, 材質一覧)
        .and_then(|常駐| packer::梱包する(材質一覧, &常駐.台帳, &常駐.フォールバック).map_err(レンダラーエラー::from))
        .and_then(|梱包| {
            let 付属資源 = 供給元.世代を仕上げる(&画像集合, &梱包.レコード列)?;
            Ok((梱包, 付属資源))
        });
    let (梱包, 付属資源) = match 結果 {
        Ok(値) => 値,
        Err(誤り) => {
            部分生成を退役させる(供給元, 画像集合, None);
            return Err(誤り);
        }
    };

    let 世代 = 資源表世代::束ねる(世代id, 梱包.レコード列, 梱包.材質別解決, 画像集合, 付属資源);
    if let Err(誤り) = completion_check::確かめる(&世代, 材質一覧) {
        let (画像集合, 付属資源) = 世代.資源を取り出す();
        部分生成を退役させる(供給元, 画像集合, 付属資源);
        return Err(誤り.into());
    }
    Ok(世代)
}

/// 公開に至らなかった世代のために作った資源を、作った本人が退役させる。フレームは一度も束縛していないためフェンスを待たない。
fn 部分生成を退役させる<供給元: 常駐テクスチャ供給元>(
    供給元: &mut 供給元,
    画像集合: Vec<供給元::常駐画像>,
    付属資源: Option<供給元::世代付属資源>,
) {
    if let Some(付属資源) = 付属資源 {
        供給元.付属資源を退役させる(付属資源);
    }
    for 画像 in 画像集合 {
        供給元.退役させる(画像);
    }
}
