//! 梱包工程が受け取る、検証済み材質1件の入力。担当するのは、材質の係数と役割ごとのテクスチャ指定を、
//! 「無し」をマジック値でなく`Option`で表したまま1つの値として運ぶことである。
//!
//! テクスチャ指定の並びは`材質テクスチャ役割::全役割`の配列添字に従う。役割の名前で受け取ってから並べ替えるのは
//! 呼び出し元の責任であり、この型は並びを組み替えない。

use crate::material::地表層の数;
use crate::vulkan::material_variant::シェーディングモデル種別;

use super::material_id::大域材質ID;
use super::texture_role::{役割の数, 材質テクスチャ役割};
use super::texture_spec::テクスチャ指定;

pub(crate) struct 梱包対象材質<'素材> {
    材質id: 大域材質ID,
    シェーディングモデル: シェーディングモデル種別,
    ベースカラー係数: [f32; 4],
    金属度係数: f32,
    粗さ係数: f32,
    役割別テクスチャ: [Option<テクスチャ指定<'素材>>; 役割の数],
    地表の層ごとのタイル倍率: [f32; 地表層の数],
}

impl<'素材> 梱包対象材質<'素材> {
    pub(crate) fn 生成する(
        材質id: 大域材質ID,
        シェーディングモデル: シェーディングモデル種別,
        ベースカラー係数: [f32; 4],
        金属度係数: f32,
        粗さ係数: f32,
        役割別テクスチャ: [Option<テクスチャ指定<'素材>>; 役割の数],
        地表の層ごとのタイル倍率: [f32; 地表層の数],
    ) -> Self {
        Self {
            材質id,
            シェーディングモデル,
            ベースカラー係数,
            金属度係数,
            粗さ係数,
            役割別テクスチャ,
            地表の層ごとのタイル倍率,
        }
    }

    pub(crate) fn 材質id(&self) -> 大域材質ID {
        self.材質id
    }

    /// 材質の3軸のうち、照明式が相互排他的に変わる軸。梱包工程が材質変種キーを導くときに読む。
    pub(crate) fn シェーディングモデル(&self) -> シェーディングモデル種別 {
        self.シェーディングモデル
    }

    pub(crate) fn ベースカラー係数(&self) -> [f32; 4] {
        self.ベースカラー係数
    }

    pub(crate) fn 金属度係数(&self) -> f32 {
        self.金属度係数
    }

    pub(crate) fn 粗さ係数(&self) -> f32 {
        self.粗さ係数
    }

    /// 地表の層の重ね合わせだけが意味を持つ欄。標準金属粗さPBRは等倍を運び、その枝の画素段は読まない。
    pub(crate) fn 地表の層ごとのタイル倍率(&self) -> [f32; 地表層の数] {
        self.地表の層ごとのタイル倍率
    }

    pub(crate) fn 役割の指定(&self, 役割: 材質テクスチャ役割) -> Option<&テクスチャ指定<'素材>> {
        self.役割別テクスチャ[役割.配列添字()].as_ref()
    }
}
