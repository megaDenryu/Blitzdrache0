//! 梱包工程が受け取る、検証済み材質1件の入力。担当するのは、材質の係数と役割ごとのテクスチャ指定を、
//! 「無し」をマジック値でなく`Option`で表したまま1つの値として運ぶことである。
//!
//! テクスチャ指定の並びは`材質テクスチャ役割::全役割`の配列添字に従う。役割の名前で受け取ってから並べ替えるのは
//! 呼び出し元の責任であり、この型は並びを組み替えない。

use super::material_id::大域材質ID;
use super::texture_role::材質テクスチャ役割;
use super::texture_spec::テクスチャ指定;

pub(crate) struct 梱包対象材質<'素材> {
    材質id: 大域材質ID,
    ベースカラー係数: [f32; 4],
    金属度係数: f32,
    粗さ係数: f32,
    役割別テクスチャ: [Option<テクスチャ指定<'素材>>; 3],
}

impl<'素材> 梱包対象材質<'素材> {
    pub(crate) fn 生成する(
        材質id: 大域材質ID,
        ベースカラー係数: [f32; 4],
        金属度係数: f32,
        粗さ係数: f32,
        役割別テクスチャ: [Option<テクスチャ指定<'素材>>; 3],
    ) -> Self {
        Self {
            材質id,
            ベースカラー係数,
            金属度係数,
            粗さ係数,
            役割別テクスチャ,
        }
    }

    pub(crate) fn 材質id(&self) -> 大域材質ID {
        self.材質id
    }

    pub(crate) fn ベースカラー係数(&self) -> [f32; 4] {
        self.ベースカラー係数
    }

    pub(crate) fn 金属度係数(&self) -> f32 {
        self.金属度係数
    }

    pub(crate) fn 粗さ係数(&self) -> f32 {
        self.粗さ係数
    }

    pub(crate) fn 役割の指定(&self, 役割: 材質テクスチャ役割) -> Option<&テクスチャ指定<'素材>> {
        self.役割別テクスチャ[役割.配列添字()].as_ref()
    }
}
