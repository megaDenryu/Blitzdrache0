//! 世代を1つも作っていない段階の材質の登録。担当するのは、レイアウト容量に照らして受け付けた材質登録簿を保つことと、
//! その内容が公開中の世代へ反映済みかどうかを覚えることである。GPU資源を1つも持たないため、この型を作ってもGPUの確保は起きない。
//!
//! 公開済みの`材質資源表`と別の型にするのは、起動時に材質を1件も持たない世代を先に公開しないためである。空の世代を公開してから
//! 起動シーンの材質で作り直すと、最初のフレームで新旧2つの世代が同時に生き、GPU資源の同時確保数が定常より正準フォールバック3枚と
//! 材質レコードバッファ1本ぶん高い位置に残る(空の世代は1フレームで退役するが、最大同時確保数は下がらない)。
//! `レイアウト容量`は世代を作り直しても変えない。`世代の作り直しが要るか`は束の出し入れで立てるだけにし、
//! 実際の作り直しはフレームの先頭で1回だけ行う。
//! 確定していない登録の受け渡しは`draft`が持つ。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「材質レコードとテクスチャ台帳」

mod draft;

use crate::draw_bundle_id::描画束ID;

use super::capacity::テクスチャ表レイアウト容量;
use super::material_id::大域材質ID;
use super::pack_input::梱包対象材質;
use super::registration::材質登録簿;

pub(crate) use draft::材質登録の下書き;

/// 1つの描画対象が持つ材質の、材質スロット素材一覧と同じ並びの大域材質ID。
pub(crate) type 描画対象別の材質ID = Vec<大域材質ID>;

pub(crate) struct 材質の登録状態 {
    レイアウト容量: テクスチャ表レイアウト容量, // パイプラインのレイアウトと同じ寿命で固定する容量
    登録簿: 材質登録簿,
    世代の作り直しが要るか: bool, // 登録簿の内容が、まだ世代として構築されていないかどうか
}

impl 材質の登録状態 {
    /// 材質を1件も持たない登録状態。起動時の呼び出し元はここへ起動シーンの材質を下書きし、最初の世代の材料にする。
    pub(crate) fn 新規(レイアウト容量: テクスチャ表レイアウト容量) -> Self {
        Self {
            レイアウト容量,
            登録簿: 材質登録簿::新規(),
            世代の作り直しが要るか: false,
        }
    }

    pub(crate) fn 束の材質を解除する(&mut self, 束id: 描画束ID) {
        if self.登録簿.束を解除する(束id) {
            self.世代の作り直しが要るか = true;
        }
    }

    pub(in crate::vulkan::material_table) const fn レイアウト容量(&self) -> テクスチャ表レイアウト容量 {
        self.レイアウト容量
    }

    /// 保持中の全材質を、世代の構築が受け取る梱包対象材質の並びとして借りる。
    pub(in crate::vulkan::material_table) fn 梱包対象を並べる(&self) -> Vec<梱包対象材質<'_>> {
        self.登録簿.梱包対象を並べる()
    }

    pub(in crate::vulkan::material_table) const fn 世代の作り直しが要るか(&self) -> bool {
        self.世代の作り直しが要るか
    }

    /// 登録簿の内容で世代を構築し終えた側が呼ぶ。次に束を出し入れするまで作り直しを起こさない。
    pub(in crate::vulkan::material_table) fn 世代へ反映済みにする(&mut self) {
        self.世代の作り直しが要るか = false;
    }

    pub(in crate::vulkan::material_table) fn 全て解除する(&mut self) {
        self.登録簿.全て解除する();
    }
}
