//! 材質テクスチャ表以外が画素段で消費するディスクリプタの枚数。担当するのは、デバイスの上限のうち表へ割けない分を
//! 名前の付いた内訳で持ち、3つの上限それぞれから表の予算を求めることである。
//!
//! 前提: 仕様は画素段に限り描画先の色添付も資源合計の上限へ数えると定める(深度は数えない)。
//! 参照: `crates/blitz_render/src/descriptor_indexing_limits.rs`

use crate::descriptor_indexing_limits::ディスクリプタ索引上限;
use crate::error::材質資源表エラー;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 画素段の予約枠 {
    表以外の画像ディスクリプタ数: u32,
    バッファのディスクリプタ数: u32,
    色添付数: u32,
}

impl 画素段の予約枠 {
    /// 現行のシーンの画素段が表以外へ使う内訳。照明問い合わせのセットの影のシャドウマップ1枚、ビューとパスのセットの定数3本と
    /// 材質のセットの材質レコードのストレージバッファでバッファ4本、描画先の色添付1枚である。
    /// 移行中は材質のセットのテクスチャ3枚も画素段が消費するが、索引表への差し替えでその3枚が表そのものになるため数えない。
    /// 参照: `crates/blitz_render/src/vulkan/descriptor/scene_set_layouts.rs`
    pub(crate) const fn 現行のシーン画素段() -> Self {
        Self {
            表以外の画像ディスクリプタ数: 1,
            バッファのディスクリプタ数: 4,
            色添付数: 1,
        }
    }

    pub(in crate::vulkan::material_table) const fn 内訳から生成する(
        表以外の画像ディスクリプタ数: u32,
        バッファのディスクリプタ数: u32,
        色添付数: u32,
    ) -> Self {
        Self {
            表以外の画像ディスクリプタ数,
            バッファのディスクリプタ数,
            色添付数,
        }
    }

    /// 3つの上限それぞれから予約枠を引き、最も厳しい値を材質テクスチャ表の予算とする。
    pub(in crate::vulkan::material_table) fn 予算を求める(
        self, 上限: ディスクリプタ索引上限
    ) -> Result<u32, 材質資源表エラー> {
        let 資源合計の予約 = self
            .表以外の画像ディスクリプタ数
            .saturating_add(self.バッファのディスクリプタ数)
            .saturating_add(self.色添付数);
        let 候補 = [
            (上限.シェーダー段あたりの画像ディスクリプタ数(), self.表以外の画像ディスクリプタ数),
            (上限.セットあたりの画像ディスクリプタ数(), self.表以外の画像ディスクリプタ数),
            (上限.シェーダー段あたりの資源合計数(), 資源合計の予約),
        ];
        let mut 予算 = u32::MAX;
        for (上限値, 予約) in 候補 {
            let Some(残り) = 上限値.checked_sub(予約).filter(|残り| *残り > 0) else {
                return Err(材質資源表エラー::予算不足 {
                    予約枚数: 予約,
                    上限: 上限値,
                });
            };
            予算 = 予算.min(残り);
        }
        Ok(予算)
    }
}
