//! 進行中フレームの保持を見て世代の退役を決める操作。触れるのは`保持状況`と`退役待ち`の2フィールドだけであり、
//! 公開中の世代と世代番号の発行には触れない。
//!
//! 不変条件: 退役するのは、公開から降りていて、かつどのフレームスロットも保持していない世代だけである。
//! 1つの世代が退役するのはちょうど1回であり、回収した時点で台帳はその世代を手放す。
//! 見送られたフレームが束縛を記録したまま次の周回まで残るのは安全側の誤差である(退役が遅れるだけで、使用中の破棄は起きない)。

use crate::vulkan::sync::フレームスロット添字;

use super::資源表世代台帳;
use crate::vulkan::material_table::generation::資源表世代;

impl<画像> 資源表世代台帳<画像> {
    /// そのスロットで発行するフレームが公開中の世代を束縛したことを記録する。
    pub(crate) fn フレームが束縛する(&mut self, スロット: フレームスロット添字) {
        let 世代 = self.公開中.世代id();
        self.保持状況.束縛を記録する(スロット, 世代);
    }

    /// そのスロットのフェンス通過を記録する。呼び出し元はフェンスを待った後にだけ呼ぶ。
    pub(crate) fn フェンス通過を記録する(&mut self, スロット: フレームスロット添字) {
        self.保持状況.通過を記録する(スロット);
    }

    /// 退役してよくなった世代を台帳から取り出す。呼び出し元は受け取った世代の画像を供給元へ退役させる。
    pub(crate) fn 退役した世代を回収する(&mut self) -> Vec<資源表世代<画像>> {
        let mut 残す = Vec::with_capacity(self.退役待ち.len());
        let mut 回収 = Vec::new();
        for 世代 in self.退役待ち.drain(..) {
            if self.保持状況.保持しているか(世代.世代id()) {
                残す.push(世代);
            } else {
                回収.push(世代);
            }
        }
        self.退役待ち = 残す;
        回収
    }

    pub(crate) fn 退役待ち件数(&self) -> usize {
        self.退役待ち.len()
    }
}
