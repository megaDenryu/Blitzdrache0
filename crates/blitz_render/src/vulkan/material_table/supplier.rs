//! 資源表世代がテクスチャをGPUへ常駐させ、世代1つぶんの束縛先を仕上げる口。担当するのは、世代の構築と退役から
//! 実際の画像資源とディスクリプタの作り方を切り離すことである。
//!
//! 本番はVulkanの画像とディスクリプタセットを作る実装を渡し、世代の状態遷移の検査は資源を持たない実装を渡す。
//! 構築と退役の手順そのものがGPUの実物に依存しないため、公開と退役の規律を狭い単体テストで固定できる。
//! 参照: `crates/blitz_render/src/vulkan/material_table/device_supplier.rs`

use crate::error::レンダラーエラー;
use crate::texture_material::テクスチャ素材;

use super::generation_record::世代内材質レコード;

pub(crate) trait 常駐テクスチャ供給元 {
    type 常駐画像;
    /// 世代1つぶんの、画像とレコード列を束ねた束縛先。材質のセットと材質レコードのストレージバッファがこれに当たる。
    type 世代付属資源;

    fn 常駐させる(&mut self, 素材: &テクスチャ素材) -> Result<Self::常駐画像, レンダラーエラー>;

    /// 画像を積み終えレコード列が確定した後に1度だけ呼び、その世代を束縛できる状態にする。
    /// 前提: `画像集合`の並びはテクスチャスロットの番号順である。
    fn 世代を仕上げる(
        &mut self,
        画像集合: &[Self::常駐画像],
        レコード列: &[世代内材質レコード],
    ) -> Result<Self::世代付属資源, レンダラーエラー>;

    /// 注意: この画像を参照しうるフレームのフェンス通過後にだけ呼ぶ。世代の退役の規律は`資源表世代台帳`が持つ。
    fn 退役させる(&mut self, 画像: Self::常駐画像);

    /// 注意: 画像と同じく、その世代を束縛したフレームのフェンス通過後にだけ呼ぶ。
    fn 付属資源を退役させる(&mut self, 付属資源: Self::世代付属資源);
}
