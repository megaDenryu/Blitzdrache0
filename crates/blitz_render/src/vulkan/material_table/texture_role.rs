//! 材質が持つテクスチャの役割。担当するのは、役割から「無しのときの正準フォールバックの用途」と
//! 「その画像をどのビュー契約で読むか」を決め切ることである。
//!
//! 役割を判別共用体にするのは、材質レコードのスロット・特徴ビット・フォールバックの3つを役割ごとに揃って扱うためである。
//! 3つのうち1つでも別の並びで持つと、法線の枠へベースカラーのスロットが入っても型が通る。
//!
//! 標準金属粗さPBRの3つと地表の層の重ね合わせの5つを1つの列挙に並べるのは、材質レコードのスロット配列が
//! シェーディングモデルに依らず1本だからである。ある材質が使わない役割は正準フォールバックのスロットを指し、
//! 特徴ビットが下りる。

use crate::material::地表層の数;
use crate::texture_material::テクスチャ用途;

use super::fallback_usage::正準フォールバック用途;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 材質テクスチャ役割 {
    ベースカラー,
    金属粗さ,
    法線マップ,
    地表の層の重み, // 地表の4層の混ぜ割合をRGBAの4成分で運ぶ画像。チャンクごとに違う
    地表の層0のタイル,
    地表の層1のタイル,
    地表の層2のタイル,
    地表の層3のタイル,
}

impl 材質テクスチャ役割 {
    /// 材質レコードのスロット配列と特徴ビットの並び順の正本。`配列添字`と同じ順に並べる。
    pub(crate) const 全役割: [Self; 役割の数] = [
        Self::ベースカラー,
        Self::金属粗さ,
        Self::法線マップ,
        Self::地表の層の重み,
        Self::地表の層0のタイル,
        Self::地表の層1のタイル,
        Self::地表の層2のタイル,
        Self::地表の層3のタイル,
    ];

    pub(crate) const fn 配列添字(self) -> usize {
        match self {
            Self::ベースカラー => 0,
            Self::金属粗さ => 1,
            Self::法線マップ => 2,
            Self::地表の層の重み => 3,
            Self::地表の層0のタイル => 4,
            Self::地表の層1のタイル => 5,
            Self::地表の層2のタイル => 6,
            Self::地表の層3のタイル => 7,
        }
    }

    /// その役割のテクスチャを持たない材質が指す既定テクスチャの用途。
    pub(crate) const fn 正準フォールバック用途(self) -> 正準フォールバック用途 {
        match self {
            Self::ベースカラー | Self::地表の層0のタイル | Self::地表の層1のタイル | Self::地表の層2のタイル | Self::地表の層3のタイル => {
                正準フォールバック用途::白
            }
            Self::金属粗さ => 正準フォールバック用途::中立金属粗さ,
            Self::法線マップ => 正準フォールバック用途::平坦法線,
            Self::地表の層の重み => 正準フォールバック用途::先頭の層だけの重み,
        }
    }

    /// 画像形式の選択に効くビュー契約。人の目に見える色だけをsRGBとして解釈する(判断23)。
    pub(crate) const fn ビュー契約(self) -> テクスチャ用途 {
        match self {
            Self::ベースカラー | Self::地表の層0のタイル | Self::地表の層1のタイル | Self::地表の層2のタイル | Self::地表の層3のタイル => {
                テクスチャ用途::色
            }
            Self::金属粗さ | Self::法線マップ | Self::地表の層の重み => テクスチャ用途::線形データ,
        }
    }
}

/// 標準金属粗さPBRの3つと、地表の層の重ね合わせの重み1つと層のタイルの合計。
pub(crate) const 役割の数: usize = 4 + 地表層の数;
