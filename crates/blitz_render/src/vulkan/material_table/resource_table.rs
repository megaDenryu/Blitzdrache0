//! レンダラーが1つだけ持つ、索引化した材質テクスチャ表の所有者。担当するのは、レイアウト容量を起動時に受け取って動かさないこと、
//! 世代台帳と材質登録簿を1つの型として保つこと、フレームの束縛と退役の記録を台帳へ取り次ぐことである。
//! 束の材質の出し入れと世代の作り直しは`publish`、材質IDからレコード添字への解決は`resolve`、
//! フレームごとの束縛とフェンス通過は`frame_binding`、供給元が要る借り物の束は`work_environment`が持つ。
//!
//! 注意: レイアウト容量は起動時に1度だけ決めて動かさない。世代ごとに要素数を変えるとセットレイアウトから作り直すことになり、
//! 「同じレイアウトの上で資源表世代だけを差し替える」設計の根幹に反する。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「材質レコードとテクスチャ台帳」

