//! レンダラーが1つだけ持つ、索引化した材質テクスチャ表の所有者。担当するのは、材質の登録状態と世代台帳を1つの型として保つこと、
//! フレームの束縛と退役の記録を台帳へ取り次ぐことである。この型が在る間は公開中の資源表世代が必ず1つ在る。
//! 束の材質の出し入れと世代の作り直しは`publish`、材質IDからレコード添字への解決は`resolve`、
//! フレームごとの束縛とフェンス通過は`frame_binding`、供給元が要る借り物の束は`work_environment`が持つ。
//!
//! 注意: レイアウト容量は起動時に1度だけ決めて動かさない。世代ごとに要素数を変えるとセットレイアウトから作り直すことになり、
//! 「同じレイアウトの上で資源表世代だけを差し替える」設計の根幹に反する。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「材質レコードとテクスチャ台帳」

mod frame_binding;
mod publish;
mod resolve;
mod work_environment;

use crate::error::レンダラーエラー;
use crate::material_table_summary::材質資源表の要約;
use crate::vulkan::texture::テクスチャ;

use super::device_supplier::{デバイス常駐供給元, 世代束縛資源};
use super::generation::資源表世代;
use super::generation_id::資源表世代ID;
use super::ledger::資源表世代台帳;
use super::registration_state::材質の登録状態;
use super::supplier::常駐テクスチャ供給元;

pub(crate) use frame_binding::資源表世代の束縛;
pub(crate) use work_environment::材質資源の作業環境;

pub(crate) struct 材質資源表 {
    登録状態: 材質の登録状態,
    台帳: 資源表世代台帳<テクスチャ, 世代束縛資源>,
}

impl 材質資源表 {
    /// 起動シーンの材質を積み終えた登録状態から最初の世代を構築し、それが通ったときだけ表を作る。
    /// 材質を1件も持たない世代を先に公開しないのは、起動直後の作り直しで新旧2つの世代が同時に生き、
    /// GPU資源の同時確保数が定常より高い位置に残るためである(参照: `registration_state`)。
    /// 構築に失敗したときは公開中の世代を1つも持たない表を作らず、型付きの失敗を返す。
    pub(crate) fn 最初の世代を公開して生成する(
        mut 登録状態: 材質の登録状態,
        環境: 材質資源の作業環境<'_>,
    ) -> Result<Self, レンダラーエラー> {
        let 最初の世代 = {
            let 材質一覧 = 登録状態.梱包対象を並べる();
            let mut 供給元 = デバイス常駐供給元::生成する(環境);
            super::generation_build::構築する(&mut 供給元, 資源表世代ID::最初(), 登録状態.レイアウト容量(), &材質一覧)?
        };
        登録状態.世代へ反映済みにする();
        Ok(Self {
            登録状態,
            台帳: 資源表世代台帳::最初の世代を公開する(最初の世代),
        })
    }

    /// 公開中の世代の版番号と中身の件数。表の内容をGPUの型なしで外から見るための計器である。
    pub(crate) fn 公開中の世代の要約(&self) -> 材質資源表の要約 {
        let 世代 = self.台帳.公開中();
        材質資源表の要約::生成する(世代.世代id().番号(), 世代.材質件数(), 世代.画像枚数())
    }

    /// 公開中の世代。材質IDの解決だけが使うため、モジュール木の外へは出さない。
    pub(in crate::vulkan::material_table) fn 公開中の世代(&self) -> &資源表世代<テクスチャ, 世代束縛資源> {
        self.台帳.公開中()
    }

    /// 前提: レンダラー全体の破棄順は`renderer/destroy.rs`が持ち、この束はGPU待機済みの1段として呼ばれる。
    /// 転送実行環境より前に呼ぶ(供給元が借りるため)。
    pub(crate) fn 破棄する(&mut self, 環境: 材質資源の作業環境<'_>) {
        self.登録状態.全て解除する();
        let mut 供給元 = デバイス常駐供給元::生成する(環境);
        for 世代 in self.台帳.全世代を取り出す() {
            退役させる(&mut 供給元, 世代);
        }
    }
}

pub(in crate::vulkan::material_table) fn 退役させる(
    供給元: &mut デバイス常駐供給元<'_>, 世代: 資源表世代<テクスチャ, 世代束縛資源>
) {
    let (画像集合, 付属資源) = 世代.資源を取り出す();
    if let Some(付属資源) = 付属資源 {
        供給元.付属資源を退役させる(付属資源);
    }
    for 画像 in 画像集合 {
        供給元.退役させる(画像);
    }
}
