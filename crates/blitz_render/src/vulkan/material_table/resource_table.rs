/// 1つの描画対象が持つ材質の、材質スロット素材一覧と同じ並びの大域材質ID。
pub(crate) type 描画対象別の材質ID = Vec<大域材質ID>;

pub(crate) struct 材質資源表 {
    /// パイプラインのレイアウトと同じ寿命で固定する容量。世代を作り直しても変えない。
    レイアウト容量: テクスチャ表レイアウト容量,
    登録簿: 材質登録簿,
    台帳: 資源表世代台帳<テクスチャ, 世代束縛資源>,
    /// 登録簿の内容が公開中の世代へまだ反映されていないかどうか。
    /// 束の出し入れではこれを立てるだけにし、実際の作り直しはフレームの先頭で1回だけ行う。
    世代の作り直しが要るか: bool,
}

impl 材質資源表 {
    /// 材質を1件も持たない最初の世代を公開して始める。正準フォールバック3枚だけが常駐する状態である。
    pub(crate) fn 生成する(
        環境: 材質資源の作業環境<'_>, レイアウト容量: テクスチャ表レイアウト容量
    ) -> Result<Self, レンダラーエラー> {
        let mut 供給元 = デバイス常駐供給元::生成する(環境);
        let 初期世代 = super::generation_build::構築する(&mut 供給元, 資源表世代ID::最初(), レイアウト容量, &[])?;
        Ok(Self {
            レイアウト容量,
            登録簿: 材質登録簿::新規(),
            台帳: 資源表世代台帳::最初の世代を公開する(初期世代),
            世代の作り直しが要るか: false,
        })
    }

    /// 公開中の世代の版番号と中身の件数。表の内容をGPUの型なしで外から見るための計器である。
    pub(crate) fn 公開中の世代の要約(&self) -> 材質資源表の要約 {
        let 世代 = self.台帳.公開中();
        材質資源表の要約::生成する(世代.世代id().番号(), 世代.材質件数(), 世代.画像枚数())
    }

    /// 公開中の世代。材質IDの解決だけが使うため、モジュール木の外へは出さない。
    pub(in crate::vulkan::material_table) fn 公開中の世代(&self) -> &資源表世代<テクスチャ, 世代束縛資源> {
        self.台帳.公開中()
    }

    /// 前提: レンダラー全体の破棄順は`renderer/destroy.rs`が持ち、この束はGPU待機済みの1段として呼ばれる。
    /// 転送実行環境より前に呼ぶ(供給元が借りるため)。
    pub(crate) fn 破棄する(&mut self, 環境: 材質資源の作業環境<'_>) {
        self.登録簿.全て解除する();
        let mut 供給元 = デバイス常駐供給元::生成する(環境);
        for 世代 in self.台帳.全世代を取り出す() {
            退役させる(&mut 供給元, 世代);
        }
    }
}

pub(in crate::vulkan::material_table) fn 退役させる(
    供給元: &mut デバイス常駐供給元<'_>, 世代: 資源表世代<テクスチャ, 世代束縛資源>
) {
    let (画像集合, 付属資源) = 世代.資源を取り出す();
    if let Some(付属資源) = 付属資源 {
        供給元.付属資源を退役させる(付属資源);
    }
    for 画像 in 画像集合 {
        供給元.退役させる(画像);
    }
}
