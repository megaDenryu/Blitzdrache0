//! 材質テクスチャ表のディスクリプタ配列の要素数。担当するのは、パイプラインのレイアウトと同じ寿命で固定する容量を、
//! デバイスの上限と要望から起動時に1度だけ決めることである。
//!
//! 注意: ディスクリプタの要素数はセットレイアウトの一部である。世代ごとに要素数を変えるとセットレイアウトごと作り直すことになり、
//! パイプラインレイアウトとパイプラインまで作り直す。「同じレイアウトの上で資源表世代だけを差し替える」という設計の根幹を守るため、
//! この容量は世代の内容で動かさない。世代が実際に常駐させる枚数がこの容量に満たない分は、一部だけ書き込んだ表の束縛
//! (descriptorBindingPartiallyBound)で未書込のまま残す。世代ごとの枚数は`世代の常駐枚数`が持つ。
//!
//! 固定の既定値(製品の最低機材要件)はまだ決めていないため、起動のたびに実機の上限と要望から決める。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「未決定の事項」

use crate::descriptor_indexing_limits::ディスクリプタ索引上限;
use crate::error::材質資源表エラー;

use super::stage_reserve::画素段の予約枠;

/// 材質テクスチャ表のディスクリプタ配列の要素数。現行アセットの固有テクスチャ数(見本の集落でも数十枚)に対して
/// 余裕を持たせた暫定値である。
/// 注意: この値はシェーダーの配列の要素数と同じでなければならない(`shaders/scene.slang`の`materialTextureTableCapacity`。
/// 一致は`cargo xtask conform`が見る)。実機の予算が足りないときに小さく切り下げられないのはこのためであり、
/// 足りない機材は型付きの失敗にする。参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「未決定の事項」
pub(in crate::vulkan::material_table) const 表の要素数: u32 = 256;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub(crate) struct テクスチャ表レイアウト容量 {
    枚数: u32,
}

impl テクスチャ表レイアウト容量 {
    /// 起動時の呼び出し元が使う唯一の入口。現行のシーンの画素段の内訳と表の要素数を、この1箇所が決める。
    pub(crate) fn 起動時に決める(上限: ディスクリプタ索引上限) -> Result<Self, 材質資源表エラー> {
        Self::決める(上限, 画素段の予約枠::現行のシーン画素段(), 表の要素数)
    }

    /// 上限から画素段の予約枠を引いた予算が要素数を賄えることを確かめる。予算のほうが小さいときに切り下げないのは、
    /// 要素数がシェーダーの配列の宣言と同じでなければならないためである。賄えない機材は必要な機能を満たさない機材として扱う。
    /// 要素数を引数のまま残すのは、最低機材要件が決まったときに出どころだけを差し替え、この導出の形を変えずに済ませるためである。
    pub(crate) fn 決める(
        上限: ディスクリプタ索引上限, 予約枠: 画素段の予約枠, 要素数: u32
    ) -> Result<Self, 材質資源表エラー> {
        let 予算枚数 = 予約枠.予算を求める(上限)?;
        if 予算枚数 < 要素数 {
            return Err(材質資源表エラー::レイアウト容量超過 {
                常駐枚数: 要素数,
                レイアウト容量: 予算枚数,
            });
        }
        Ok(Self { 枚数: 要素数 })
    }

    pub(crate) const fn 枚数(self) -> u32 {
        self.枚数
    }
}
