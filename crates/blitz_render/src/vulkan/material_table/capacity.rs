//! 1つの資源表世代が置けるテクスチャの枚数。担当するのは、デバイスの上限から画素段の予約枠を引いた予算と実際に要る枚数を
//! 突き合わせ、ディスクリプタを1つも作る前に容量超過を型付きの失敗にすることである。
//!
//! 容量を必要枚数ちょうどにするのは、表を世代ごとに作り直す設計では余分な枠を先に確保しても使い道が無いためである。
//! 固定の既定値(製品の最低機材要件)はまだ決めていないため、起動のたびに実機の上限と現行アセットの必要数から決める。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「未決定の事項」

use crate::descriptor_indexing_limits::ディスクリプタ索引上限;
use crate::error::材質資源表エラー;

use super::stage_reserve::画素段の予約枠;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub(crate) struct テクスチャ表容量 {
    枚数: u32,
}

impl テクスチャ表容量 {
    pub(crate) fn 決める(
        上限: ディスクリプタ索引上限, 予約枠: 画素段の予約枠, 必要枚数: u32
    ) -> Result<Self, 材質資源表エラー> {
        let 予算枚数 = 予約枠.予算を求める(上限)?;
        if 必要枚数 > 予算枚数 {
            return Err(材質資源表エラー::容量超過 { 必要枚数, 予算枚数 });
        }
        Ok(Self { 枚数: 必要枚数 })
    }

    pub(crate) const fn 枚数(self) -> u32 {
        self.枚数
    }
}
