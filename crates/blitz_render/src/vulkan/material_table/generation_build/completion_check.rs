//! 公開する直前の完成検査。受け取るのは組み上げた世代と材質一覧で、返すのは「その世代が完全に構築済みか」の判定である。
//!
//! この検査があるから、フレームは束縛した世代のどの材質IDも解決でき、どのレコードのスロットも実在する画像を指すと言い切れる。
//! 完全に構築済みの世代だけを公開するという規律が、GPU使用中のディスクリプタ書き換えを初期要件から外す根拠である。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「ディスクリプタ索引の採用範囲」

use crate::error::材質資源表エラー;
use crate::vulkan::material_table::generation::資源表世代;
use crate::vulkan::material_table::pack_input::梱包対象材質;
use crate::vulkan::material_table::texture_role::材質テクスチャ役割;

pub(super) fn 確かめる<画像, 付属>(
    世代: &資源表世代<画像, 付属>, 材質一覧: &[梱包対象材質<'_>]
) -> Result<(), 材質資源表エラー> {
    let 画像枚数 = u32::try_from(世代.画像枚数()).unwrap_or_else(|_| panic!("世代の画像枚数がu32に収まらない"));
    for 材質 in 材質一覧 {
        let 参照 = 世代.解決する(材質.材質id())?;
        let 添字 = 世代.描画へ渡すレコード添字(参照)?;
        let Some(レコード) = 世代.レコード(添字) else {
            return Err(材質資源表エラー::未知の材質ID {
                材質id: 材質.材質id().値()
            });
        };
        for 役割 in 材質テクスチャ役割::全役割 {
            let スロット = レコード.スロット(役割);
            if スロット.添字() >= 画像枚数 {
                return Err(材質資源表エラー::スロットが範囲外 {
                    材質id: 材質.材質id().値(),
                    スロット: スロット.添字(),
                    画像枚数,
                });
            }
        }
    }
    Ok(())
}
