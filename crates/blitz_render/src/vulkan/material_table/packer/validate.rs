//! 梱包した材質レコード1件の整合検査。担当するのは、特徴ビットとテクスチャスロットとデータが同じ材質から
//! 同時に決まっているかを、レコードを作った直後に確かめることである。
//!
//! ビットとスロットの対応を検査するのは、ビットが立っているのに解決していないスロットを持つレコードが
//! シェーダーの分岐の誤りで未定義アクセスになるためである。無効な添字を放置する設計を採らない根拠でもある。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「材質レコードとテクスチャ台帳」

use crate::error::材質資源表エラー;
use crate::vulkan::material_table::generation_record::世代内材質レコード;
use crate::vulkan::material_table::material_id::大域材質ID;
use crate::vulkan::material_table::texture_role::材質テクスチャ役割;

use super::fallback_slots::正準フォールバック解決;

pub(super) fn 梱包した材質レコードの整合を検証する(
    材質id: 大域材質ID,
    レコード: &世代内材質レコード,
    フォールバック: &正準フォールバック解決,
) -> Result<(), 材質資源表エラー> {
    for 係数 in レコード.全係数() {
        if !係数.is_finite() || !(0.0..=1.0).contains(&係数) {
            return Err(材質資源表エラー::係数の範囲外 {
                材質id: 材質id.値(), 係数
            });
        }
    }
    for 役割 in 材質テクスチャ役割::全役割 {
        let フォールバックのスロット = フォールバック.用途で引く(役割.正準フォールバック用途());
        let 実際のスロット = レコード.スロット(役割);
        let 解決済みか = 実際のスロット != フォールバックのスロット;
        if レコード.特徴集合().役割を持つか(役割) != 解決済みか {
            return Err(材質資源表エラー::特徴ビットとスロットの不整合 { 材質id: 材質id.値() });
        }
    }
    Ok(())
}
