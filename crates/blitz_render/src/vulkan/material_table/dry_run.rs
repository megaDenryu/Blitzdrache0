//! GPU資源を1つも作らずに世代の構築を試すための供給元。担当するのは、容量と梱包の整合という決定的な失敗を、
//! 画像もバッファもディスクリプタも作る前に確かめられるようにすることである。
//!
//! 本番の供給元と同じ構築の手順を通すのは、検査だけ別の規則で判定すると、試しに通ったのに本番で落ちる組が
//! できてしまうためである。ここが作らないのはGPUの実物だけであり、必要枚数の数え方も梱包も完成検査も本番と同一である
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「材質レコードとテクスチャ台帳」)。

use crate::error::レンダラーエラー;
use crate::texture_material::テクスチャ素材;

use super::generation_record::世代内材質レコード;
use super::supplier::常駐テクスチャ供給元;

pub(in crate::vulkan::material_table) struct 検査専用供給元;

impl 常駐テクスチャ供給元 for 検査専用供給元 {
    /// 画像そのものを持たない。スロットの発番と並びの一致は台帳と世代の構築が数だけで確かめる。
    type 常駐画像 = ();
    type 世代付属資源 = ();

    fn 常駐させる(&mut self, _素材: &テクスチャ素材) -> Result<(), レンダラーエラー> {
        Ok(())
    }

    fn 世代を仕上げる(
        &mut self, _画像集合: &[()], _レコード列: &[世代内材質レコード]
    ) -> Result<(), レンダラーエラー> {
        Ok(())
    }

    fn 退役させる(&mut self, _画像: ()) {}

    fn 付属資源を退役させる(&mut self, _付属資源: ()) {}
}
