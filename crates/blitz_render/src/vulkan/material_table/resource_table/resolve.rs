//! 描画発行が指す材質IDを、そのフレームが束縛した資源表世代の中でのレコード添字へ写す操作。
//! 触れるのは台帳の公開中の世代だけであり、登録簿にも退役にも触れない。
//!
//! 束縛の版番号を引数で受け取って照合するのは、束縛から発行までの間に世代が差し替わっていないことを確かめるためである。
//! 照合を省くと、公開中の世代で解決した添字を、GPUが別の世代の表を読んでいるフレームへ載せてしまう
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「材質レコードとテクスチャ台帳」)。

use crate::error::材質資源表エラー;

use super::super::generation_resolution::世代内材質解決;
use super::super::material_id::大域材質ID;
use super::{材質資源表, 資源表世代の束縛};

impl 材質資源表 {
    /// 返すのは描画発行が要る2つ、すなわちGPUの描画定数へ載せるレコード添字と、その発行が束縛するPSOを選ぶ材質変種キーである。
    pub(crate) fn 束縛した世代で材質を解決する(
        &self,
        束縛: 資源表世代の束縛,
        材質id: 大域材質ID,
    ) -> Result<世代内材質解決, 材質資源表エラー> {
        let 世代 = self.公開中の世代();
        if 世代.世代id() != 束縛.世代id {
            return Err(材質資源表エラー::異世代の混在 {
                参照の世代: 束縛.世代id.番号(),
                束縛する世代: 世代.世代id().番号(),
            });
        }
        let 参照 = 世代.解決する(材質id)?;
        世代.描画へ渡す解決(参照)
    }
}
