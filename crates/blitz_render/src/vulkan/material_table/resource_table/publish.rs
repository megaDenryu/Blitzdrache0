//! 束の材質の出し入れを登録状態へ取り次ぎ、その結果を1つの新しい資源表世代として公開する局面。触れるのは登録状態と台帳の2つである。
//!
//! 出し入れと作り直しを分けるのは、1フレームのうちに束が何個増減しても作る世代を1つに保つためである。
//! 束ごとに作り直すと、同時に生きている世代の数がそのフレームの束の増減数で変わり、GPU資源の同時確保数が
//! ストリーミングの進み方で揺れる。フレームの先頭で1回だけ作り直せば、生きている世代は公開中と進行中フレーム数ぶんに収まる。
//!
//! 注意: 公開に成功するまで公開中の世代を触らない。構築の途中で失敗したら、その世代のために作った資源だけを退役させて
//! 型付きの失敗を返すため、作り直しに失敗しても表示中の絵は変わらない。

use crate::draw_bundle_id::描画束ID;
use crate::error::レンダラーエラー;
use crate::render_object_material::描画対象素材;

use super::super::device_supplier::デバイス常駐供給元;
use super::super::generation_build;
use super::super::registration_state::{描画対象別の材質ID, 材質登録の下書き};
use super::{材質資源の作業環境, 材質資源表};

impl 材質資源表 {
    /// 束1つぶんの材質を下書きとして積む。返すのは描画対象ごと材質スロットごとの大域材質IDと、確定と取り消しに使う下書きである。
    pub(crate) fn 束の材質を下書きする(
        &mut self,
        束id: 描画束ID,
        描画対象一覧: &[描画対象素材],
    ) -> Result<(Vec<描画対象別の材質ID>, 材質登録の下書き), レンダラーエラー> {
        self.登録状態.束の材質を下書きする(束id, 描画対象一覧)
    }

    /// 下書きを確定し、次のフレームの先頭で世代を作り直すことを予約する。
    pub(crate) fn 下書きを確定する(&mut self, 下書き: 材質登録の下書き) {
        self.登録状態.下書きを確定する(下書き);
    }

    /// 下書きを捨てて、下書きを始める前の状態へ戻す。
    pub(crate) fn 下書きを取り消す(&mut self, 下書き: 材質登録の下書き) {
        self.登録状態.下書きを取り消す(下書き);
    }

    pub(crate) fn 束の材質を解除する(&mut self, 束id: 描画束ID) {
        self.登録状態.束の材質を解除する(束id);
    }

    /// 登録簿の内容が公開中の世代へ反映されていなければ、保持中の全ての束の材質から世代を1つ作り直して公開する。
    /// 前提: そのフレームがまだ世代を束縛していないうちに呼ぶ(束縛した後で差し替えると、GPUが読む表と解決した添字がずれる)。
    pub(crate) fn 世代を最新にする(&mut self, 環境: 材質資源の作業環境<'_>) -> Result<(), レンダラーエラー> {
        if !self.登録状態.世代の作り直しが要るか() {
            return Ok(());
        }
        let 世代id = self.台帳.次の世代idを発行する()?;
        let 新世代 = {
            let 材質一覧 = self.登録状態.梱包対象を並べる();
            let mut 供給元 = デバイス常駐供給元::生成する(環境);
            generation_build::構築する(&mut 供給元, 世代id, self.登録状態.レイアウト容量(), &材質一覧)?
        };
        self.台帳.公開する(新世代);
        self.登録状態.世代へ反映済みにする();
        Ok(())
    }
}
