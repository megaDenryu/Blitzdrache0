//! フレーム1つぶんの資源表世代の束縛とフェンス通過の記録。触れるのは世代台帳だけであり、登録簿にもレイアウト容量にも触れない。
//! 呼ばれるのは毎フレームちょうど1回ずつであり、束の出し入れとは呼び出し頻度が異なる。
//!
//! 不変条件: 1つのフレームスロットは、束縛とフェンス通過をこの順で交互に繰り返す。順が崩れると、GPUが読んでいる最中の
//! 世代を誰も保持していないと台帳が誤判定する(その検出は`フレーム保持状況`が持つ)。
//!
//! 束縛先を借りることと保持を記録することを分けるのは、フレームの準備が送信の前に失敗しうるためである。
//! 借りるだけなら状態を変えないため、準備の途中で失敗しても未送信のスロットが世代を保持したままにならない。

use ash::vk;

use crate::vulkan::sync::フレームスロット添字;

use super::super::device_supplier::デバイス常駐供給元;
use super::super::generation_id::資源表世代ID;
use super::{材質資源の作業環境, 材質資源表, 退役させる};

/// そのフレームが束縛する資源表世代の束縛先と版番号。版番号を一緒に運ぶのは、描画発行が解決した材質GPU参照が
/// 同じ世代のものであることを確かめる材料だからである。
#[derive(Clone, Copy)]
pub(crate) struct 資源表世代の束縛 {
    pub(crate) 材質のセット: vk::DescriptorSet,
    pub(crate) 世代id: 資源表世代ID,
}

impl 材質資源表 {
    /// 公開中の世代の束縛先を借りる。状態を1つも変えないため、この後の準備が失敗しても何も残らない。
    pub(crate) fn 公開中の束縛を借りる(&self) -> 資源表世代の束縛 {
        let 世代 = self.台帳.公開中();
        資源表世代の束縛 {
            材質のセット: 世代.付属資源().材質のセット(),
            世代id: 世代.世代id(),
        }
    }

    /// そのフレームが公開中の世代を束縛したことを記録する。
    /// 前提: 呼び出し元はコマンドをキューへ送り終えてから呼ぶ。送る前に記録すると、準備が失敗して送信へ到達しなかった
    /// スロットが世代を保持したままになり、次にそのスロットを使うフレームの束縛が呼び出し順の誤りとして落ちる。
    /// 注意: フェンス通過を記録していないスロットへ重ねて呼ぶのは呼び出し順の誤りであり、その場で落ちる。
    pub(crate) fn フレームの保持を記録する(&mut self, スロット: フレームスロット添字) {
        self.台帳.フレームが束縛する(スロット);
    }

    /// そのスロットのフェンス通過を記録し、誰も保持しなくなった世代の資源を退役させる。
    /// 前提: 呼び出し元がそのスロットのフェンスを待った直後に呼ぶ。
    pub(crate) fn フェンス通過を記録して退役させる(
        &mut self, 環境: 材質資源の作業環境<'_>, スロット: フレームスロット添字
    ) {
        self.台帳.フェンス通過を記録する(スロット);
        let 回収 = self.台帳.退役した世代を回収する();
        if 回収.is_empty() {
            return;
        }
        let mut 供給元 = デバイス常駐供給元::生成する(環境);
        for 世代 in 回収 {
            退役させる(&mut 供給元, 世代);
        }
    }
}
