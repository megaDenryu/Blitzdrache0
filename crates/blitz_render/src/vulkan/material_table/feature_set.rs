//! GPUの材質レコードが持つ、直交して有無が変わる機能のビット集合。担当するのは、テクスチャの有無から導いたビットを
//! 対応するスロットと必ず同時に決めさせることである。
//!
//! 注意: 下位3ビットの番号はアセット側の正本と同じ並びにする。食い違うと、アセットが焼いた特徴集合とGPUのレコードが別の機能を指す。
//! 地表の層の5本はアセットの直列化に現れない。その枝は重みも層のタイルも必ず持つため、有無を運ぶ欄が要らないからである。
//! 参照: `crates/blitz_engine/src/asset/pbr_material_data/features.rs`

use super::texture_role::{役割の数, 材質テクスチャ役割};

const ベースカラーテクスチャ有のビット: u32 = 0b0000_0001;
const 金属粗さテクスチャ有のビット: u32 = 0b0000_0010;
const 法線テクスチャ有のビット: u32 = 0b0000_0100;
/// 以下の5本は地表の層の重ね合わせの枝だけが立てる。ビット番号は役割の配列添字と同じ並びである。
const 地表の層の重みテクスチャ有のビット: u32 = 0b0000_1000;
const 地表の層0のタイル有のビット: u32 = 0b0001_0000;
const 地表の層1のタイル有のビット: u32 = 0b0010_0000;
const 地表の層2のタイル有のビット: u32 = 0b0100_0000;
const 地表の層3のタイル有のビット: u32 = 0b1000_0000;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub(crate) struct 材質特徴集合 {
    生値: u32,
}

impl 材質特徴集合 {
    /// 生のビット列を受け取る生成関数を持たないのは、対応するテクスチャスロットと食い違うビットを外から作れないようにするためである。
    /// ビットとスロットを1つの組にする不変条件は`世代内材質レコード::組み立てる`が持ち、この導出はその材料を作るだけである。
    pub(crate) fn 役割ごとの有無から導出する(有無: [bool; 役割の数]) -> Self {
        let mut 生値 = 0;
        for 役割 in 材質テクスチャ役割::全役割 {
            if 有無[役割.配列添字()] {
                生値 |= 役割のビット(役割);
            }
        }
        Self { 生値 }
    }

    pub(crate) fn 役割を持つか(self, 役割: 材質テクスチャ役割) -> bool {
        self.生値 & 役割のビット(役割) != 0
    }

    /// GPU境界: 材質レコードへ載せる固定幅の値。
    pub(crate) const fn 生値(self) -> u32 {
        self.生値
    }
}

const fn 役割のビット(役割: 材質テクスチャ役割) -> u32 {
    match 役割 {
        材質テクスチャ役割::ベースカラー => ベースカラーテクスチャ有のビット,
        材質テクスチャ役割::金属粗さ => 金属粗さテクスチャ有のビット,
        材質テクスチャ役割::法線マップ => 法線テクスチャ有のビット,
        材質テクスチャ役割::地表の層の重み => 地表の層の重みテクスチャ有のビット,
        材質テクスチャ役割::地表の層0のタイル => 地表の層0のタイル有のビット,
        材質テクスチャ役割::地表の層1のタイル => 地表の層1のタイル有のビット,
        材質テクスチャ役割::地表の層2のタイル => 地表の層2のタイル有のビット,
        材質テクスチャ役割::地表の層3のタイル => 地表の層3のタイル有のビット,
    }
}
