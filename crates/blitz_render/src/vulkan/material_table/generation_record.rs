//! 1つの資源表世代の中に置く材質1件の記述。担当するのは、係数・特徴ビット・役割ごとのテクスチャスロットを、
//! 梱包工程が同時に決めた1つの組として保つことである。
//!
//! 注意: この3つを別々に組み立ててはならない。ビットが立っているのに解決していないスロットを持つ組は、
//! シェーダーが実在しない画像を参照する未定義動作になる。生成をこのモジュール木の内側に限り、整合の検証は梱包工程が持つ。
//! シェーディングモデルと表面描画状態は持たない(パイプラインキー側が知るため、レコードへ二重に持たない)。
//! `役割別スロット`の並びは`材質テクスチャ役割::全役割`が正本である。
//! `地表の層ごとのタイル倍率`は、層のタイルを何倍で貼るかをUVへ掛ける係数である。

use crate::material::地表層の数;

use super::feature_set::材質特徴集合;
use super::texture_role::{役割の数, 材質テクスチャ役割};
use super::texture_slot::テクスチャスロット;

pub(crate) struct 世代内材質レコード {
    ベースカラー係数: [f32; 4],
    金属度係数: f32,
    粗さ係数: f32,
    特徴集合: 材質特徴集合,
    役割別スロット: [テクスチャスロット; 役割の数], // 役割の配列添字の並びで持つ
    地表の層ごとのタイル倍率: [f32; 地表層の数],    // 地表の層の重ね合わせだけが意味を持つ欄
}

impl 世代内材質レコード {
    pub(in crate::vulkan::material_table) fn 組み立てる(
        ベースカラー係数: [f32; 4],
        金属度係数: f32,
        粗さ係数: f32,
        特徴集合: 材質特徴集合,
        役割別スロット: [テクスチャスロット; 役割の数],
        地表の層ごとのタイル倍率: [f32; 地表層の数],
    ) -> Self {
        Self {
            ベースカラー係数,
            金属度係数,
            粗さ係数,
            特徴集合,
            役割別スロット,
            地表の層ごとのタイル倍率,
        }
    }

    pub(crate) fn ベースカラー係数(&self) -> [f32; 4] {
        self.ベースカラー係数
    }

    pub(crate) fn 金属度係数(&self) -> f32 {
        self.金属度係数
    }

    pub(crate) fn 粗さ係数(&self) -> f32 {
        self.粗さ係数
    }

    pub(crate) fn 特徴集合(&self) -> 材質特徴集合 {
        self.特徴集合
    }

    pub(crate) fn スロット(&self, 役割: 材質テクスチャ役割) -> テクスチャスロット {
        self.役割別スロット[役割.配列添字()]
    }

    pub(crate) fn 地表の層ごとのタイル倍率(&self) -> [f32; 地表層の数] {
        self.地表の層ごとのタイル倍率
    }

    /// GPUバイト列の並びの検査だけが使う組み立て。本番は梱包工程だけがこの型を作る。
    #[cfg(test)]
    pub(crate) fn 試験用に組み立てる(
        ベースカラー係数: [f32; 4],
        金属度係数: f32,
        粗さ係数: f32,
        役割ごとの有無: [bool; 役割の数],
        役割別スロット番号: [u32; 役割の数],
        地表の層ごとのタイル倍率: [f32; 地表層の数],
    ) -> Self {
        Self::組み立てる(
            ベースカラー係数,
            金属度係数,
            粗さ係数,
            材質特徴集合::役割ごとの有無から導出する(役割ごとの有無),
            役割別スロット番号.map(テクスチャスロット::生成する),
            地表の層ごとのタイル倍率,
        )
    }

    /// 全ての係数を1つの列として読む。範囲の検証が係数を1つずつ名指しせずに済む。
    pub(in crate::vulkan::material_table) fn 全係数(&self) -> [f32; 6] {
        let [赤, 緑, 青, 不透明度] = self.ベースカラー係数;
        [赤, 緑, 青, 不透明度, self.金属度係数, self.粗さ係数]
    }
}
