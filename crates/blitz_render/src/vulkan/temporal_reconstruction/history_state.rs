//! 履歴画像がフレームをまたいで持つ状態。触れるのは交互に使う2枚のどちらへ書くかと、履歴を混ぜてよいかの2つだけであり、
//! 画像そのものもパスも知らない。
//!
//! 2つを1つの型に置くのは、どちらも「提示まで到達したフレームだけが進める」という同じ規律で動くためである。
//! 見送られたフレームは履歴画像へ1画素も書かないため、そこで交代させると次のフレームがまだ書かれていない側を読む。
//!
//! 交代の周期を進行中フレーム数へ合わせてはならない。スロットごとに履歴を分けると、あるフレームが読むのは
//! 1つ前でなく2つ前の結果になり、混合の系列が2本に割れる
//! (`参照: _doc/設計/時間再構成.md`「判断c: 履歴画像の持ち方と無効化の規律」)。

use super::images::履歴の枚数;

/// 履歴の中身を今のフレームへ混ぜてよいか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum 履歴の有効性 {
    /// 直前に無効化が起きており、履歴の中身が今の絵に対応していない。混ぜずに今のフレームの結果をそのまま出す。
    無効,
    有効,
}

/// 履歴の書き込み先と有効性。
pub(crate) struct 履歴の状態 {
    書き添字: usize,
    有効性: 履歴の有効性,
}

impl 履歴の状態 {
    /// 確保した直後は、2枚とも零で埋めただけで今の絵に対応する内容を持たない。
    pub(crate) fn 無効で生成する() -> Self {
        Self {
            書き添字: 0,
            有効性: 履歴の有効性::無効,
        }
    }

    /// このフレームが結果を書き込む側。
    pub(crate) fn 書き添字(&self) -> usize {
        self.書き添字
    }

    /// このフレームが前のフレームの結果として読む側。
    pub(crate) fn 読み添字(&self) -> usize {
        (self.書き添字 + 1) % 履歴の枚数
    }

    /// 履歴を今のフレームへ混ぜてよいか。無効の間は混ぜず、今のフレームの結果をそのまま出す。
    pub(crate) fn 混ぜるか(&self) -> bool {
        self.有効性 == 履歴の有効性::有効
    }

    /// 判断cの3条件(視点の不連続な差し替え・スワップチェーンの作り直し・シェーダーまたはアセットの再読込)が
    /// 起きたときに呼ぶ。書き込み先は動かさない。動かすと、まだ読まれていない側が読み側へ回る。
    pub(crate) fn 無効にする(&mut self) {
        self.有効性 = 履歴の有効性::無効;
    }

    /// 提示まで到達したフレームの後で呼ぶ。書き込んだ側を次のフレームの読み側へ回し、履歴を有効にする。
    pub(crate) fn 提示したフレームを反映する(&mut self) {
        self.書き添字 = self.読み添字();
        self.有効性 = 履歴の有効性::有効;
    }
}
