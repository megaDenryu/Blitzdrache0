//! 画面寸法の変更への追従。4枚を作り直し、履歴には初期値を書き直してディスクリプタを結び直す。
//! 呼び出しタイミング: リサイズ・陳腐化でスワップチェーンを作り直した直後(GPU待機済み)。
//!
//! 新しい画像を作ってから古い画像を破棄するため、画像生成が失敗しても呼び出し前の一式がそのまま残り、
//! 保持側は一部だけが欠けた状態を見ない。交換の間だけ新旧の画像が同時に存在する分のGPUメモリを使う。
//!
//! 履歴の内容を引き継がず、履歴を無効へ戻すのは、スワップチェーンの作り直しが判断cの無効化条件の1つだからである。
//! 寸法の変わった画面へ前の寸法の履歴を混ぜる意味は無い。

use ash::vk;

use super::images::時間再構成の画像組;
use super::{時間再構成一式, 画面の入力};
use crate::error::レンダラーエラー;
use crate::vulkan::tracked_device::GPUデバイス;
use crate::vulkan::transfer::転送実行環境;

impl 時間再構成一式 {
    /// 前提: 呼び出し時点でGPUがこれらの画像とディスクリプタを使用していないこと(device_wait_idle後)。
    pub(crate) fn 寸法に追従する(
        &mut self,
        device: &GPUデバイス,
        メモリプロパティ: &vk::PhysicalDeviceMemoryProperties,
        転送環境: &転送実行環境,
        画面: 画面の入力,
    ) -> Result<(), レンダラーエラー> {
        let 新画像組 = 時間再構成の画像組::生成する(device, メモリプロパティ, 画面.寸法)?;
        if let Err(誤り) = self.履歴の初期値を書く(device, 転送環境, &新画像組) {
            新画像組.破棄する(device);
            return Err(誤り);
        }
        let 旧画像組 = std::mem::replace(&mut self.画像組, 新画像組);
        旧画像組.破棄する(device);
        self.履歴を無効にする();
        self.資源を束縛する(device, 画面.深度ビュー);
        Ok(())
    }
}
