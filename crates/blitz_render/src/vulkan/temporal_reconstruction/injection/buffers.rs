//! 合成入力のホスト可視バッファの本数を保つ工程と、確保した本数ぶんをまとめて解放する工程。
//! 受け取るのは確保済みバッファの並び、返すのは4本の配列か解放の完了である。
//!
//! 独立した工程にするのは、確保が途中で失敗したときの片付けと、破棄のときの片付けが同じ操作だからである。
//! 2箇所へ書くと、片方だけが解放を落とした状態が台帳の残数としてしか現れない。

use crate::vulkan::allocator::専用メモリ付きバッファ;
use crate::vulkan::tracked_device::GPUデバイス;

/// 前提: 呼び出し元が唯一の所有者であり、破棄時点でGPU側の使用がdevice_wait_idle済みであることを保証する。
pub(super) fn 注入のバッファ一覧を片付ける(device: &GPUデバイス, 一覧: &[専用メモリ付きバッファ]) {
    for バッファ in 一覧 {
        バッファ.破棄する(device);
    }
}

/// 確保した本数が4本と一致することは呼び出し元の繰り返しが保証している。一致しない状態は呼び出し元の誤りである。
pub(super) fn 配列にする(確保済み: Vec<専用メモリ付きバッファ>) -> [専用メモリ付きバッファ; 4] {
    let 本数 = 確保済み.len();
    確保済み
        .try_into()
        .unwrap_or_else(|_| panic!("合成入力のバッファを4本確保するはずが{本数}本だった(実装のバグ)"))
}
