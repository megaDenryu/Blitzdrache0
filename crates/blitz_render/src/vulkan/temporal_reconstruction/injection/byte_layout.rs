//! 合成入力の成分列を、転送がそのまま読めるバイトの並びへ写す工程。受け取るのは単精度の成分列、返すのはバイト列である。
//!
//! 独立した工程にするのは、写す先の形式が画像ごとに違うためである。色と履歴と動きベクトルは半精度、深度は単精度であり、
//! どちらの丸めもGPUが同じ形式へ書くときと同じでなければ、CPU正本が「GPUが保つ値」と別の値から結果を作る。

use crate::numeric::half_precision::単精度を半精度へ;

/// 半精度の画像へ書き戻す3枚は、単精度の成分列を半精度へ丸めて並べる。丸めはGPUが同じ形式へ書くときと同じである。
pub(super) fn 半精度のバイト列へ写す(成分列: &[f32]) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(成分列.len() * 2);
    for 値 in 成分列 {
        バイト列.extend_from_slice(&単精度を半精度へ(*値).to_le_bytes());
    }
    バイト列
}

/// 深度画像はD32_SFLOATであるため、単精度をそのままリトルエンディアンで並べた列が転送の中身になる。
pub(super) fn 単精度のバイト列へ写す(成分列: &[f32]) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(成分列.len() * 4);
    for 値 in 成分列 {
        バイト列.extend_from_slice(&値.to_le_bytes());
    }
    バイト列
}
