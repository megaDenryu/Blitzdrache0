//! 材質の3軸のうち、照明式が相互排他的に変わる軸。担当するのは、シェーディングモデルを判別共用体で表し、
//! 相互排他な照明式が同時に有効な材質を作れなくすることである。
//!
//! ビット集合にしないのは、表面下散乱と髪と水を同時に立てた材質を表現できてしまうためである。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「材質の3軸」

/// `地表の層の重ね合わせ`は、アルベドを4層のタイルの重み付き混ぜ合わせから作る地表の材質である。
/// ベースカラー1枚を読む`標準金属粗さPBR`とは照明式へ渡す入力の組み立てが相互排他に変わるため、
/// 特徴ビットでなく枝で分ける(参照: `_doc/設計/マルチマテリアルと材質境界.md`「地表の層の重ね合わせ」)。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub(crate) enum シェーディングモデル種別 {
    標準金属粗さPBR,
    地表の層の重ね合わせ,
}

impl シェーディングモデル種別 {
    /// 失敗の表示で使う名前。枝が増えたときに網羅検査へ載せるため、`match`で書く。
    pub(crate) const fn 名前(self) -> &'static str {
        match self {
            Self::標準金属粗さPBR => "標準金属粗さPBR",
            Self::地表の層の重ね合わせ => "地表の層の重ね合わせ",
        }
    }
}
