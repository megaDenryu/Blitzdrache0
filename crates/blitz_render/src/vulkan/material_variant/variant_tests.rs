//! 材質変種キーの導出の検査。能力表が全組合せをちょうど1回ずつ並べていること、特徴集合の8通りが同じキーへ畳まれること、
//! 未対応の表面描画状態が型付きの失敗になることを見る。

#![allow(clippy::unwrap_used)]

use super::capability_table;
use super::shading_model::シェーディングモデル種別;
use super::surface_state::{アルファ様式, 深度書込, 表面描画状態, 面の向き};
use super::three_axes::材質の3軸;
use super::variant_key::材質変種キー;
use crate::vulkan::material_table::材質特徴集合;

fn 全組合せ() -> Vec<表面描画状態> {
    let mut 一覧 = Vec::new();
    for アルファ in [アルファ様式::不透明, アルファ様式::マスク, アルファ様式::ブレンド] {
        for 面 in [面の向き::片面, 面の向き::両面] {
            for 深度 in [深度書込::書く, 深度書込::書かない] {
                一覧.push(表面描画状態::生成する(アルファ, 面, 深度));
            }
        }
    }
    一覧
}

#[test]
fn 能力表は表面描画状態の全組合せをちょうど1回ずつ持つ() {
    let 全行 = capability_table::能力表の全行(シェーディングモデル種別::標準金属粗さPBR);
    for 状態 in 全組合せ() {
        assert_eq!(
            全行.iter().filter(|登録| **登録 == 状態).count(),
            1,
            "{状態:?}が能力表にちょうど1行でない"
        );
    }
    assert_eq!(全行.len(), 全組合せ().len(), "能力表の行数が全組合せの数と違う");
}

#[test]
fn テクスチャの有無8通りは同じ正規化済み変種へ畳まれる() {
    for 生値 in 0u32..8 {
        let 有無 = [生値 & 1 != 0, 生値 & 2 != 0, 生値 & 4 != 0];
        let 特徴集合 = 材質特徴集合::役割ごとの有無から導出する(有無);
        let 三軸 = 材質の3軸::生成する(シェーディングモデル種別::標準金属粗さPBR, 特徴集合, 表面描画状態::不透明両面());
        assert_eq!(三軸.変種キーへ正規化する().unwrap(), 材質変種キー::標準金属粗さPBRの不透明両面);
    }
}

#[test]
fn 不透明両面以外の表面描画状態は型付きで拒む() {
    let 特徴集合 = 材質特徴集合::役割ごとの有無から導出する([false; 3]);
    for 状態 in 全組合せ() {
        let 三軸 = 材質の3軸::生成する(シェーディングモデル種別::標準金属粗さPBR, 特徴集合, 状態);
        let 結果 = 三軸.変種キーへ正規化する();
        if 状態 == 表面描画状態::不透明両面() {
            assert!(結果.is_ok(), "不透明両面を拒んだ");
        } else {
            assert!(結果.is_err(), "{状態:?}を通した");
        }
    }
}

#[test]
fn 同じ3軸からは常に同じキーが出る() {
    let 特徴集合 = 材質特徴集合::役割ごとの有無から導出する([true, false, true]);
    let 三軸 = 材質の3軸::生成する(シェーディングモデル種別::標準金属粗さPBR, 特徴集合, 表面描画状態::不透明両面());
    assert_eq!(三軸.変種キーへ正規化する().unwrap(), 三軸.変種キーへ正規化する().unwrap());
}
