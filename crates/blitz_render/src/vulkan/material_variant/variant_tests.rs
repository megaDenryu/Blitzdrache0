//! 材質変種キーの導出の検査。能力表がモデルごとに全組合せをちょうど1回ずつ並べていること、特徴集合の8通りが同じキーへ畳まれること、
//! 不透明両面だけがモデルごとの変種へ写り、それ以外の表面描画状態が型付きの失敗になることを見る。

#![allow(clippy::unwrap_used)]

use super::capability_table;
use super::shading_model::シェーディングモデル種別;
use super::surface_state::{アルファ様式, 深度書込, 表面描画状態, 面の向き};
use super::three_axes::材質の3軸;
use super::variant_key::材質変種キー;
use crate::vulkan::material_table::{役割の数, 材質特徴集合};

/// 地表の層の重ね合わせが立てる役割の有無。重み1つと層のタイル4つを必ず持ち、標準金属粗さPBRの3つは持たない。
const 地表の層の役割の有無: [bool; 役割の数] = [false, false, false, true, true, true, true, true];

fn 全組合せ() -> Vec<表面描画状態> {
    let mut 一覧 = Vec::new();
    for アルファ in [アルファ様式::不透明, アルファ様式::マスク, アルファ様式::ブレンド] {
        for 面 in [面の向き::片面, 面の向き::両面] {
            for 深度 in [深度書込::書く, 深度書込::書かない] {
                一覧.push(表面描画状態::生成する(アルファ, 面, 深度));
            }
        }
    }
    一覧
}

/// 標準金属粗さPBRの3役割だけを立てた有無の並び。地表の層の5役割はこの枝が持たないため常に偽である。
fn 標準金属粗さpbrの有無(生値: u32) -> [bool; 役割の数] {
    let mut 有無 = [false; 役割の数];
    有無[0] = 生値 & 1 != 0;
    有無[1] = 生値 & 2 != 0;
    有無[2] = 生値 & 4 != 0;
    有無
}

#[test]
fn 能力表はどのモデルでも表面描画状態の全組合せをちょうど1回ずつ持つ() {
    for モデル in [シェーディングモデル種別::標準金属粗さPBR, シェーディングモデル種別::地表の層の重ね合わせ]
    {
        let 全行 = capability_table::能力表の全行(モデル);
        for 状態 in 全組合せ() {
            let 件数 = 全行.iter().filter(|登録| **登録 == 状態).count();
            assert_eq!(件数, 1, "{モデル:?}の{状態:?}が能力表にちょうど1行でない");
        }
        assert_eq!(全行.len(), 全組合せ().len(), "{モデル:?}の能力表の行数が全組合せの数と違う");
    }
}

#[test]
fn テクスチャの有無8通りは同じ正規化済み変種へ畳まれる() {
    for 生値 in 0u32..8 {
        let 特徴集合 = 材質特徴集合::役割ごとの有無から導出する(標準金属粗さpbrの有無(生値));
        let 三軸 = 材質の3軸::生成する(シェーディングモデル種別::標準金属粗さPBR, 特徴集合, 表面描画状態::不透明両面());
        assert_eq!(三軸.変種キーへ正規化する().unwrap(), 材質変種キー::標準金属粗さPBRの不透明両面);
    }
}

#[test]
fn 不透明両面だけがモデルごとの変種へ写り他は型付きで拒む() {
    let 組一覧 = [
        (
            シェーディングモデル種別::標準金属粗さPBR,
            標準金属粗さpbrの有無(0),
            材質変種キー::標準金属粗さPBRの不透明両面,
        ),
        (
            シェーディングモデル種別::地表の層の重ね合わせ,
            地表の層の役割の有無,
            材質変種キー::地表の層の重ね合わせの不透明両面,
        ),
    ];
    for (モデル, 有無, 期待キー) in 組一覧 {
        let 特徴集合 = 材質特徴集合::役割ごとの有無から導出する(有無);
        for 状態 in 全組合せ() {
            let 結果 = 材質の3軸::生成する(モデル, 特徴集合, 状態).変種キーへ正規化する();
            if 状態 == 表面描画状態::不透明両面() {
                assert_eq!(結果.unwrap(), 期待キー, "{モデル:?}の不透明両面が別のキーへ写った");
            } else {
                assert!(結果.is_err(), "{モデル:?}が{状態:?}を通した");
            }
        }
    }
}

#[test]
fn 同じ3軸からは常に同じキーが出る() {
    let 特徴集合 = 材質特徴集合::役割ごとの有無から導出する(標準金属粗さpbrの有無(0b101));
    let 三軸 = 材質の3軸::生成する(シェーディングモデル種別::標準金属粗さPBR, 特徴集合, 表面描画状態::不透明両面());
    assert_eq!(三軸.変種キーへ正規化する().unwrap(), 三軸.変種キーへ正規化する().unwrap());
}
