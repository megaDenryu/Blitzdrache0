//! シェーディングモデルごとに、描けると宣言した表面描画状態の組合せの一覧を持つ台帳と、モデルからその一覧を参照する工程。
//! ここが持つのは表そのものと参照だけであり、参照した結果をどう扱うか(未対応の失敗の組み立て)は親が持つ。
//!
//! 台帳を親から分けるのは、シェーディングモデルが増えるたびにこの一覧だけが12行ずつ伸び、導出の手順と押し合うためである。
//! 表が全組合せを並べるのは、描ける組合せだけを並べると「表に無い組合せ」が未検討なのか未対応なのかを
//! 読み手が区別できないためである。行を消さずに判定だけを書き換えることで、対応範囲の変化が差分に現れる。
//! 描ける1行が両面なのは、実物のシーンのパイプラインがカリングを無効にしているためである。表の判定は実物の固定機能と一致させる。

use super::super::shading_model::シェーディングモデル種別;
use super::super::surface_state::アルファ様式::{ブレンド, マスク, 不透明};
use super::super::surface_state::深度書込::{書かない, 書く};
use super::super::surface_state::面の向き::{両面, 片面};
use super::super::surface_state::{アルファ様式, 深度書込, 表面描画状態, 面の向き};
use super::super::variant_key::材質変種キー;

/// 1つの組合せに対する判定。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 描画能力 {
    対応する(材質変種キー),
    対応しない,
}

const 標準金属粗さPBRの不透明両面の変種: 描画能力 = 描画能力::対応する(材質変種キー::標準金属粗さPBRの不透明両面);
const 地表の層の重ね合わせの不透明両面の変種: 描画能力 = 描画能力::対応する(材質変種キー::地表の層の重ね合わせの不透明両面);
const 未対応: 描画能力 = 描画能力::対応しない;

/// 表の1行を短く書くための組み立て。3つの軸の並びをここ1箇所に固定する。
const fn 状態(アルファ: アルファ様式, 面: 面の向き, 深度: 深度書込) -> 表面描画状態 {
    表面描画状態::生成する(アルファ, 面, 深度)
}

/// 標準金属粗さPBRの表面描画状態の全組合せと、その組合せを描けるかどうか。
const 標準金属粗さPBRの能力表: [(表面描画状態, 描画能力); 12] = [
    (状態(不透明, 片面, 書く), 未対応),
    (状態(不透明, 片面, 書かない), 未対応),
    (状態(不透明, 両面, 書く), 標準金属粗さPBRの不透明両面の変種),
    (状態(不透明, 両面, 書かない), 未対応),
    (状態(マスク, 片面, 書く), 未対応),
    (状態(マスク, 片面, 書かない), 未対応),
    (状態(マスク, 両面, 書く), 未対応),
    (状態(マスク, 両面, 書かない), 未対応),
    (状態(ブレンド, 片面, 書く), 未対応),
    (状態(ブレンド, 片面, 書かない), 未対応),
    (状態(ブレンド, 両面, 書く), 未対応),
    (状態(ブレンド, 両面, 書かない), 未対応),
];

/// 地表の層の重ね合わせの表面描画状態の全組合せと、その組合せを描けるかどうか。描ける行が標準金属粗さPBRと同じ1行なのは、
/// この変種が同じ固定機能で描かれ、違うのが画素段のアルベドの組み立てだけだからである。
const 地表の層の重ね合わせの能力表: [(表面描画状態, 描画能力); 12] = [
    (状態(不透明, 片面, 書く), 未対応),
    (状態(不透明, 片面, 書かない), 未対応),
    (状態(不透明, 両面, 書く), 地表の層の重ね合わせの不透明両面の変種),
    (状態(不透明, 両面, 書かない), 未対応),
    (状態(マスク, 片面, 書く), 未対応),
    (状態(マスク, 片面, 書かない), 未対応),
    (状態(マスク, 両面, 書く), 未対応),
    (状態(マスク, 両面, 書かない), 未対応),
    (状態(ブレンド, 片面, 書く), 未対応),
    (状態(ブレンド, 片面, 書かない), 未対応),
    (状態(ブレンド, 両面, 書く), 未対応),
    (状態(ブレンド, 両面, 書かない), 未対応),
];

pub(super) fn モデルの表を参照する(モデル: シェーディングモデル種別) -> [(表面描画状態, 描画能力); 12] {
    match モデル {
        シェーディングモデル種別::標準金属粗さPBR => 標準金属粗さPBRの能力表,
        シェーディングモデル種別::地表の層の重ね合わせ => 地表の層の重ね合わせの能力表,
    }
}
