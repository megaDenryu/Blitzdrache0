//! 描けると宣言した組合せの閉じた一覧と、そこから正規化済みの材質変種キーを引く導出。担当するのは、
//! 材質能力の検証表の正本を1箇所へ置くことである。
//!
//! 表が全組合せを並べるのは、描ける組合せだけを並べると「表に無い組合せ」が未検討なのか未対応なのかを
//! 読み手が区別できないためである。行を消さずに判定だけを書き換えることで、対応範囲の変化が差分に現れる。
//! 材質特徴集合がこの表に現れないのは、現行の画素段が特徴ビットを読まず、テクスチャを持たない役割も正準フォールバックの
//! スロットを標本するため、8通りのどれもシェーダーと固定機能を変えないからである(参照: `three_axes`)。
//! 描ける1行が両面なのは、実物のシーンのパイプラインがカリングを無効にしているためである。表の判定は実物の固定機能と一致させる。
//! 一致していないと、実際には描いている状態を「描けない」と拒み、拒んでいる状態を実際には描くことになる。

use super::error::材質能力エラー;
use super::shading_model::シェーディングモデル種別;
use super::surface_state::アルファ様式::{ブレンド, マスク, 不透明};
use super::surface_state::深度書込::{書かない, 書く};
use super::surface_state::面の向き::{両面, 片面};
use super::surface_state::{アルファ様式, 深度書込, 表面描画状態, 面の向き};
use super::variant_key::材質変種キー;

/// 1つの組合せに対する判定。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum 描画能力 {
    対応する(材質変種キー),
    対応しない,
}

const 不透明両面の変種: 描画能力 = 描画能力::対応する(材質変種キー::標準金属粗さPBRの不透明両面);
const 未対応: 描画能力 = 描画能力::対応しない;

/// 表の1行を短く書くための組み立て。3つの軸の並びをここ1箇所に固定する。
const fn 状態(アルファ: アルファ様式, 面: 面の向き, 深度: 深度書込) -> 表面描画状態 {
    表面描画状態::生成する(アルファ, 面, 深度)
}

/// 標準金属粗さPBRの表面描画状態の全組合せと、その組合せを描けるかどうか。
const 標準金属粗さPBRの能力表: [(表面描画状態, 描画能力); 12] = [
    (状態(不透明, 片面, 書く), 未対応),
    (状態(不透明, 片面, 書かない), 未対応),
    (状態(不透明, 両面, 書く), 不透明両面の変種),
    (状態(不透明, 両面, 書かない), 未対応),
    (状態(マスク, 片面, 書く), 未対応),
    (状態(マスク, 片面, 書かない), 未対応),
    (状態(マスク, 両面, 書く), 未対応),
    (状態(マスク, 両面, 書かない), 未対応),
    (状態(ブレンド, 片面, 書く), 未対応),
    (状態(ブレンド, 片面, 書かない), 未対応),
    (状態(ブレンド, 両面, 書く), 未対応),
    (状態(ブレンド, 両面, 書かない), 未対応),
];

/// 3軸のうちモデルと表面描画状態から正規化済みのキーを引く。表に無い組合せは表の不備であり、
/// 未対応として黙って通すと能力表が正本である根拠が崩れるため、その場で落とす。
pub(super) fn 引く(
    モデル: シェーディングモデル種別, 状態: 表面描画状態
) -> Result<材質変種キー, 材質能力エラー> {
    let 表 = match モデル {
        シェーディングモデル種別::標準金属粗さPBR => 標準金属粗さPBRの能力表,
    };
    let Some((_, 能力)) = 表.iter().find(|(登録, _)| *登録 == 状態) else {
        panic!("材質能力表が表面描画状態の全組合せを網羅しているという不変条件に違反した: {状態:?}");
    };
    match 能力 {
        描画能力::対応する(キー) => Ok(*キー),
        描画能力::対応しない => {
            let (アルファ, 面, 深度) = 状態.名前の組();
            Err(材質能力エラー::未対応の表面描画状態 {
                モデル: モデル.名前(),
                アルファ,
                面,
                深度,
            })
        }
    }
}

/// 表が全組合せをちょうど1回ずつ並べていることの検査だけが読む。
#[cfg(test)]
pub(super) fn 能力表の全行(モデル: シェーディングモデル種別) -> Vec<表面描画状態> {
    match モデル {
        シェーディングモデル種別::標準金属粗さPBR => 標準金属粗さPBRの能力表.iter().map(|(状態, _)| *状態).collect(),
    }
}
