//! 材質の3軸のうちモデルと表面描画状態から、正規化済みの材質変種キーを引く導出。担当するのは、
//! 表に無い組合せを黙って通さないことと、未対応の組合せを型付きの失敗にすることである。
//!
//! 描けると宣言した組合せの表そのものは`model_tables`が持つ。材質特徴集合がこの表に現れないのは、
//! 現行の画素段が特徴ビットを読まず、テクスチャを持たない役割も正準フォールバックのスロットを標本するため、
//! 有無の組合せがどれもシェーダーと固定機能を変えないからである(参照: `three_axes`)。

mod model_tables;

use super::error::材質能力エラー;
use super::shading_model::シェーディングモデル種別;
use super::surface_state::表面描画状態;
use super::variant_key::材質変種キー;
use model_tables::描画能力;

/// 3軸のうちモデルと表面描画状態から正規化済みのキーを引く。表に無い組合せは表の不備であり、
/// 未対応として黙って通すと能力表が正本である根拠が崩れるため、その場で落とす。
pub(super) fn 引く(
    モデル: シェーディングモデル種別, 状態: 表面描画状態
) -> Result<材質変種キー, 材質能力エラー> {
    let 表 = model_tables::モデルの表を引く(モデル);
    let Some((_, 能力)) = 表.iter().find(|(登録, _)| *登録 == 状態) else {
        panic!("材質能力表が表面描画状態の全組合せを網羅しているという不変条件に違反した: {状態:?}");
    };
    match 能力 {
        描画能力::対応する(キー) => Ok(*キー),
        描画能力::対応しない => {
            let (アルファ, 面, 深度) = 状態.名前の組();
            Err(材質能力エラー::未対応の表面描画状態 {
                モデル: モデル.名前(),
                アルファ,
                面,
                深度,
            })
        }
    }
}

/// 表が全組合せをちょうど1回ずつ並べていることの検査だけが読む。
#[cfg(test)]
pub(super) fn 能力表の全行(モデル: シェーディングモデル種別) -> Vec<表面描画状態> {
    model_tables::モデルの表を引く(モデル).iter().map(|(状態, _)| *状態).collect()
}
