//! 材質の3軸を正規化して得たキー。担当するのは、実際にシェーダーと固定機能を変える区別だけを枝として持つことである。
//!
//! 注意: 原材料の軸をそのまま枝にしてはならない。テクスチャの有無8通りを別の枝にすると、同じシェーダーと同じ固定機能の
//! パイプラインが8本生成される。枝を増やしてよいのは、その枝が別のシェーダーか別の固定機能を要求するときだけである。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段6

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub(crate) enum 材質変種キー {
    /// 標準金属粗さPBRを不透明・両面(カリングなし)・深度書込ありで描く変種。材質特徴集合の8通りはすべてこの枝へ写る。
    /// 面の向きが両面なのは、実物のシーンのパイプラインがカリングを無効にしているためである。片面の枝は、入力が面の向きを
    /// 実行時形式で運ぶようになり、カリングを有効にしたパイプラインを実際に作るときに足す。
    標準金属粗さPBRの不透明両面,
}

impl 材質変種キー {
    /// 現行のエンジンが描ける全変種。パイプライン台帳が起動時に数え上げる必要キー集合の出どころである。
    pub(crate) const 全変種: [Self; 1] = [Self::標準金属粗さPBRの不透明両面];
}
