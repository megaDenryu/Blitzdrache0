//! 材質の3軸が、このエンジンが描けると宣言した組合せの外にあったときの失敗。
//!
//! 「未知の値」と「既知だが未対応の組合せ」を分けないのは、3軸がすべて判別共用体であり未知の値を表現できないためである。
//! 未知の値の拒否はアセットの読込境界(材質特徴集合の生値からの復元)が担う。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「材質の3軸」

use thiserror::Error;

#[derive(Debug, Error, Clone, PartialEq, Eq)]
pub enum 材質能力エラー {
    #[error("シェーディングモデル{モデル}は表面描画状態(アルファ{アルファ}・{面}・深度書込{深度})を描けない")]
    未対応の表面描画状態 {
        モデル: &'static str,
        アルファ: &'static str,
        面: &'static str,
        深度: &'static str,
    },
}
