use super::スワップチェーン画像添字;

#[test]
fn 取得した値をそのままgpu境界へ戻す() {
    assert_eq!(スワップチェーン画像添字::取得結果から生成する(3).gpu境界用u32(), 3);
}

#[test]
fn 配列添字は取得した値と一致する() {
    assert_eq!(スワップチェーン画像添字::取得結果から生成する(0).配列添字(), 0);
    assert_eq!(スワップチェーン画像添字::取得結果から生成する(2).配列添字(), 2);
}

#[test]
fn u32上限でも変換できる() {
    let 添字 = スワップチェーン画像添字::取得結果から生成する(u32::MAX);
    assert_eq!(添字.配列添字(), usize::try_from(u32::MAX).unwrap_or(0));
}
