//! 自動露出のセットへ4つの資源を書き込む工程。
//! 呼び出しタイミング: 生成直後と、スワップチェーン再構築でHDR中間画像を作り直した直後(どちらもGPU未使用の時点)。
//!
//! 触れるのはディスクリプタセット1つだけであり、バッファもHDR中間画像も引数で受け取る。

use ash::vk;

use super::自動露出一式;
use crate::vulkan::descriptor::結ぶ現物;

impl 自動露出一式 {
    /// 前提: 呼び出し時点でGPUがこのセットを使用していないこと(生成直後またはdevice_wait_idle後)。
    ///
    /// 注意: 画像のレイアウトは`画像用途::シェーダー読みコンピュート段`が導くSHADER_READ_ONLY_OPTIMALと一致させる。
    /// 食い違うとvalidationがディスクリプタのレイアウト不一致を報告する。
    pub(crate) fn 資源を束縛する(&self, device: &ash::Device, hdrビュー: vk::ImageView) {
        self.ディスクリプタ.セット.書き込み先(device).並びの位置ごとに結ぶ([
            結ぶ現物::サンプラー無しの画像 {
                ビュー: hdrビュー,
                レイアウト: vk::ImageLayout::SHADER_READ_ONLY_OPTIMAL,
            },
            結ぶ現物::バッファ全体(self.バッファ.境界.バッファのハンドル()),
            結ぶ現物::バッファ全体(self.バッファ.ヒストグラム.バッファのハンドル()),
            結ぶ現物::バッファ全体(self.バッファ.露出状態.バッファのハンドル()),
        ]);
    }
}
