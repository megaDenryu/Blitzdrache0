//! slangの構造体の宣言を読み取れなかったことを表す型付きエラー。破れうる前提を枝で数え上げる。
//!
//! 読めなかったことを「一致した」と読み替えないため、どの前提が破れたかを型で言う。宣言が消えた・
//! 閉じていない・並びの規則が決まっていない型が現れたの3つは、直し方がそれぞれ違う。

use thiserror::Error;

#[derive(Debug, Error)]
pub(crate) enum シェーダー構造体の読み取りの破れ {
    #[error("{構造体名}の宣言が見つからない")]
    宣言が見つからない { 構造体名: String },
    #[error("{構造体名}の宣言が閉じていない")]
    宣言が閉じていない { 構造体名: String },
    #[error("フィールドの宣言として読めない: {行}")]
    フィールドの宣言として読めない { 行: String },
    #[error("バイト詰めの規則が決まっていない型である: {型名}")]
    バイト詰めの規則が決まっていない型である { 型名: String },
    #[error("配列の要素数を数として読めない: {綴り}({誤り})")]
    配列の要素数を数として読めない { 綴り: String, 誤り: std::num::ParseIntError },
}
