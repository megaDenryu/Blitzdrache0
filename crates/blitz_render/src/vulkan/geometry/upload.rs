//! ステージングバッファ経由でデバイスローカルバッファへアップロードする
//! (判断20: 頂点/インデックス共通の転送基盤)。

use ash::vk;

use crate::error::レンダラーエラー;
use crate::vulkan::allocator::{GPU資源の確保係, 専用メモリ付きバッファ};
use crate::vulkan::command_sink::積み込みを開始したコマンドバッファ;
use crate::vulkan::transfer::転送実行環境;

pub(crate) fn ステージング経由でアップロードする(
    確保係: &GPU資源の確保係<'_>,
    転送環境: &転送実行環境,
    データ: &[u8],
    用途: vk::BufferUsageFlags,
) -> Result<専用メモリ付きバッファ, レンダラーエラー> {
    let ステージング = 確保係.ホスト可視バッファを確保して書き込む(データ, vk::BufferUsageFlags::TRANSFER_SRC)?;

    let バイト数 = u64::try_from(データ.len()).unwrap_or_else(|_| panic!("転送データ長がu64に収まらない"));
    let 転送先 = match 確保係.デバイスローカルバッファを確保する(バイト数, 用途 | vk::BufferUsageFlags::TRANSFER_DST) {
        Ok(転送先) => 転送先,
        Err(誤り) => {
            ステージング.破棄する(確保係.論理デバイス());
            return Err(誤り);
        }
    };

    let コピー結果 = ステージングバッファから転送先バッファへコピーする(
        転送環境,
        ステージング.バッファのハンドル(),
        転送先.バッファのハンドル(),
        バイト数,
    );
    ステージング.破棄する(確保係.論理デバイス());

    if let Err(誤り) = コピー結果 {
        転送先.破棄する(確保係.論理デバイス());
        return Err(誤り);
    }
    Ok(転送先)
}

fn ステージングバッファから転送先バッファへコピーする(
    転送環境: &転送実行環境,
    ステージングバッファ: vk::Buffer,
    先バッファ: vk::Buffer,
    バイト数: u64,
) -> Result<(), レンダラーエラー> {
    let 一時 = 転送環境.転送コマンドを積み始める()?;
    let 領域 = [vk::BufferCopy::default().size(バイト数)];
    // 安全性: command_bufferは積み込み開始済み。両バッファは直前に生成済みで、
    // コピー長は両方の確保サイズ以下(同一データ長で確保しているため一致)。
    let 積み先 = 一時.積み先();
    unsafe {
        積み先
            .論理デバイス()
            .cmd_copy_buffer(積み先.コマンドバッファ(), ステージングバッファ, 先バッファ, &領域);
    }
    一時.送信して完了を待つ()
}
