//! 材質テクスチャ表の索引化に要る物理デバイスの能力。2機能の対応状況を持ち、欠けている機能を答える。
//! 非対応は品質の枝ではなく可否であるため、満たさない機材は選定で候補から外し、1台も残らなければ明示的な失敗にする。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「ディスクリプタ索引の採用範囲」。
//!
//! 注意: ここが持つのは採取と照合だけであり、同じ2機能をデバイス生成で有効化するのは
//! `crates/blitz_render/src/vulkan/device.rs`である。片方だけを増減させると、選定を通った機材で
//! 有効化していない機能をシェーダーが使う。
//! 物理デバイスからの読み取りは`query`が持ち、採取した上限は公開の値オブジェクト`ディスクリプタ索引上限`が持つ。

#[cfg(test)]
mod descriptor_indexing_tests;
mod query;

pub(crate) use query::{上限を採取する, 機能を採取する};

use crate::error::ディスクリプタ索引機能項目;

/// 物理デバイスから読み取った、索引化に要る2機能の対応状況。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct ディスクリプタ索引機能 {
    非一様な添字での画像参照: bool,
    一部だけ書き込んだ表の束縛: bool,
}

impl ディスクリプタ索引機能 {
    pub(crate) fn 生成する(非一様な添字での画像参照: bool, 一部だけ書き込んだ表の束縛: bool) -> Self {
        Self {
            非一様な添字での画像参照,
            一部だけ書き込んだ表の束縛,
        }
    }

    /// 最低要件のうち欠けている機能。満たしていれば空になる。
    pub(crate) fn 不足一覧(self) -> Vec<ディスクリプタ索引機能項目> {
        ディスクリプタ索引機能項目::全項目
            .into_iter()
            .filter(|項目| !self.対応しているか(*項目))
            .collect()
    }

    pub(crate) fn 最低要件を満たすか(self) -> bool {
        self.不足一覧().is_empty()
    }

    fn 対応しているか(self, 項目: ディスクリプタ索引機能項目) -> bool {
        match 項目 {
            ディスクリプタ索引機能項目::非一様な添字での画像参照 => self.非一様な添字での画像参照,
            ディスクリプタ索引機能項目::一部だけ書き込んだ表の束縛 => self.一部だけ書き込んだ表の束縛,
        }
    }
}
