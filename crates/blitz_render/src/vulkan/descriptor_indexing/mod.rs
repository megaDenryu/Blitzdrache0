//! 材質テクスチャ表の索引化に要る物理デバイスの能力を、エンジンの最低機能要件と照合する。
//! 非対応は品質の枝ではなく可否であるため、満たさない機材は明示的な失敗にする。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「ディスクリプタ索引の採用範囲」。
//!
//! 注意: この段では照合と上限の採取だけを行い、機能をデバイス生成で有効化しない。有効化は
//! シェーダーとディスクリプタ表の作り直しを伴い既存の絵と判定値を動かすため、索引材質段まで持ち越す。
//! 物理デバイスからの読み取りは`query`が、テクスチャ表の容量に効く上限は`limits`が持つ。

#[cfg(test)]
mod descriptor_indexing_tests;
mod limits;
mod query;

pub(crate) use limits::ディスクリプタ索引上限;
pub(crate) use query::採取する;

use crate::error::{ディスクリプタ索引機能項目, デバイス要件エラー};

/// 物理デバイスから読み取った、索引化に要る3機能の対応状況。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct ディスクリプタ索引機能 {
    実行時のディスクリプタ配列: bool,
    非一様な添字での画像参照: bool,
    一部だけ書き込んだ表の束縛: bool,
}

impl ディスクリプタ索引機能 {
    pub(crate) fn 生成する(
        実行時のディスクリプタ配列: bool, 非一様な添字での画像参照: bool, 一部だけ書き込んだ表の束縛: bool
    ) -> Self {
        Self {
            実行時のディスクリプタ配列,
            非一様な添字での画像参照,
            一部だけ書き込んだ表の束縛,
        }
    }

    /// 最低要件を満たすなら成功、満たさないなら欠けた機能を並べた型付きエラーを返す。
    pub(crate) fn 最低要件を照合する(self) -> Result<(), デバイス要件エラー> {
        let 不足一覧: Vec<ディスクリプタ索引機能項目> = ディスクリプタ索引機能項目::全項目
            .into_iter()
            .filter(|項目| !self.対応しているか(*項目))
            .collect();
        if 不足一覧.is_empty() {
            return Ok(());
        }
        Err(デバイス要件エラー::ディスクリプタ索引機能不足(不足一覧))
    }

    fn 対応しているか(self, 項目: ディスクリプタ索引機能項目) -> bool {
        match 項目 {
            ディスクリプタ索引機能項目::実行時のディスクリプタ配列 => self.実行時のディスクリプタ配列,
            ディスクリプタ索引機能項目::非一様な添字での画像参照 => self.非一様な添字での画像参照,
            ディスクリプタ索引機能項目::一部だけ書き込んだ表の束縛 => self.一部だけ書き込んだ表の束縛,
        }
    }
}
