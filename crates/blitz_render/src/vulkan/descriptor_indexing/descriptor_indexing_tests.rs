//! 採取した機能が、欠けている項目をそのまま答えることの検査。物理デバイスの実物に依存しないよう、
//! 採取結果と同じ形の値を直に組み立てて判定だけを見る。実機での照合成功は`cargo xtask smoke`の完走が示す。
//! 候補が複数あるときの選び分けは`physical_device/choose_tests.rs`が見る。

use super::ディスクリプタ索引機能;
use crate::error::ディスクリプタ索引機能項目;

#[test]
fn 三機能がそろえば最低要件を満たす() {
    let 機能 = ディスクリプタ索引機能::生成する(true, true, true);
    assert!(機能.最低要件を満たすか());
    assert!(機能.不足一覧().is_empty());
}

#[test]
fn 実行時のディスクリプタ配列を欠くとその機能だけが不足になる() {
    let 機能 = ディスクリプタ索引機能::生成する(false, true, true);
    assert!(!機能.最低要件を満たすか());
    assert_eq!(機能.不足一覧(), vec![ディスクリプタ索引機能項目::実行時のディスクリプタ配列]);
}

#[test]
fn 非一様な添字での画像参照を欠くとその機能だけが不足になる() {
    let 機能 = ディスクリプタ索引機能::生成する(true, false, true);
    assert_eq!(機能.不足一覧(), vec![ディスクリプタ索引機能項目::非一様な添字での画像参照]);
}

#[test]
fn 一部だけ書き込んだ表の束縛を欠くとその機能だけが不足になる() {
    let 機能 = ディスクリプタ索引機能::生成する(true, true, false);
    assert_eq!(機能.不足一覧(), vec![ディスクリプタ索引機能項目::一部だけ書き込んだ表の束縛]);
}

#[test]
fn 全て欠くと三機能が定義順に並ぶ() {
    let 機能 = ディスクリプタ索引機能::生成する(false, false, false);
    assert_eq!(機能.不足一覧(), ディスクリプタ索引機能項目::全項目.to_vec());
}

#[test]
fn 上限は採取した値をそのまま返す() {
    let 上限 = super::ディスクリプタ索引上限::生成する(200_000, 1_048_576, 4_294_967_295);
    assert_eq!(上限.シェーダー段あたりの画像ディスクリプタ数(), 200_000);
    assert_eq!(上限.セットあたりの画像ディスクリプタ数(), 1_048_576);
    assert_eq!(上限.シェーダー段あたりの資源合計数(), 4_294_967_295);
}
