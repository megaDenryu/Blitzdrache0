//! 最低機能要件の照合が、欠けた機能をそのまま報告することの検査。物理デバイスの実物に依存しないよう、
//! 採取結果と同じ形の値を直に組み立てて判定だけを見る。実機での照合成功は`cargo xtask smoke`の完走が示す。

use super::ディスクリプタ索引機能;
use crate::error::{ディスクリプタ索引機能項目, デバイス要件エラー};

fn 不足一覧を取り出す(機能: ディスクリプタ索引機能) -> Vec<ディスクリプタ索引機能項目> {
    match 機能.最低要件を照合する() {
        Ok(()) => Vec::new(),
        Err(デバイス要件エラー::ディスクリプタ索引機能不足(不足一覧)) => 不足一覧,
        Err(誤り) => panic!("ディスクリプタ索引の不足以外のエラーが返った: {誤り}"),
    }
}

#[test]
fn 三機能がそろえば照合を通る() {
    assert!(ディスクリプタ索引機能::生成する(true, true, true).最低要件を照合する().is_ok());
}

#[test]
fn 実行時のディスクリプタ配列を欠くとその機能だけが不足になる() {
    let 不足一覧 = 不足一覧を取り出す(ディスクリプタ索引機能::生成する(false, true, true));
    assert_eq!(不足一覧, vec![ディスクリプタ索引機能項目::実行時のディスクリプタ配列]);
}

#[test]
fn 非一様な添字での画像参照を欠くとその機能だけが不足になる() {
    let 不足一覧 = 不足一覧を取り出す(ディスクリプタ索引機能::生成する(true, false, true));
    assert_eq!(不足一覧, vec![ディスクリプタ索引機能項目::非一様な添字での画像参照]);
}

#[test]
fn 一部だけ書き込んだ表の束縛を欠くとその機能だけが不足になる() {
    let 不足一覧 = 不足一覧を取り出す(ディスクリプタ索引機能::生成する(true, true, false));
    assert_eq!(不足一覧, vec![ディスクリプタ索引機能項目::一部だけ書き込んだ表の束縛]);
}

#[test]
fn 全て欠くと三機能が定義順に並ぶ() {
    let 不足一覧 = 不足一覧を取り出す(ディスクリプタ索引機能::生成する(false, false, false));
    assert_eq!(不足一覧, ディスクリプタ索引機能項目::全項目.to_vec());
}

/// 欠けた機能をVulkanの綴りで読めることまでを検査する。エラーの型だけでは、どれを直せば動くのかが利用者に伝わらない。
#[test]
fn エラーメッセージが欠けた機能の綴りを並べる() {
    let 誤り = ディスクリプタ索引機能::生成する(false, true, false)
        .最低要件を照合する()
        .err()
        .map(|誤り| 誤り.to_string())
        .unwrap_or_default();
    assert!(誤り.contains("runtimeDescriptorArray"), "実際のメッセージ: {誤り}");
    assert!(誤り.contains("descriptorBindingPartiallyBound"), "実際のメッセージ: {誤り}");
    assert!(!誤り.contains("shaderSampledImageArrayNonUniformIndexing"), "実際のメッセージ: {誤り}");
}

#[test]
fn 上限は採取した値をそのまま返す() {
    let 上限 = super::ディスクリプタ索引上限::生成する(200_000, 1_048_576);
    assert_eq!(上限.シェーダー段あたりの画像ディスクリプタ数(), 200_000);
    assert_eq!(上限.セットあたりの画像ディスクリプタ数(), 1_048_576);
}
