//! 索引化した材質テクスチャ表の容量に効く、物理デバイスの上限。触れるのは採取した2つの数だけであり、
//! 値をそのまま保って読み出させる。
//!
//! 注意: この型は合否を判定しない。テクスチャ表の容量の既定値がまだ決まっておらず、手元の1機材の上限を
//! そのまま最低要件にすると対象機材を不当に狭めるためである。既定値の確定とセットで判定を足す。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「未決定の事項」。

/// サンプラーと分離した読み取り専用の画像ディスクリプタ(VK_DESCRIPTOR_TYPE_SAMPLED_IMAGE)を、
/// 1つのシェーダー段と1つのディスクリプタセットがそれぞれいくつ参照できるかの上限。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct ディスクリプタ索引上限 {
    /// maxPerStageDescriptorSampledImages。
    シェーダー段あたりの画像ディスクリプタ数: u32,
    /// maxDescriptorSetSampledImages。
    セットあたりの画像ディスクリプタ数: u32,
}

impl ディスクリプタ索引上限 {
    pub(crate) fn 生成する(
        シェーダー段あたりの画像ディスクリプタ数: u32, セットあたりの画像ディスクリプタ数: u32
    ) -> Self {
        Self {
            シェーダー段あたりの画像ディスクリプタ数,
            セットあたりの画像ディスクリプタ数,
        }
    }

    pub(crate) fn シェーダー段あたりの画像ディスクリプタ数(self) -> u32 {
        self.シェーダー段あたりの画像ディスクリプタ数
    }

    pub(crate) fn セットあたりの画像ディスクリプタ数(self) -> u32 {
        self.セットあたりの画像ディスクリプタ数
    }
}
