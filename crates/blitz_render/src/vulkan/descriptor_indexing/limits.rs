//! 索引化した材質テクスチャ表の容量に効く、物理デバイスの上限。触れるのは採取した3つの数だけであり、
//! 値をそのまま保って読み出させる。
//!
//! 注意: この型は合否を判定しない。テクスチャ表の容量の既定値がまだ決まっておらず、手元の1機材の上限を
//! そのまま最低要件にすると対象機材を不当に狭めるためである。既定値の確定とセットで判定を足す。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「未決定の事項」。

/// 材質テクスチャ表が実際に何枚まで置けるかを決める3つの上限。画像ディスクリプタそのものの上限2つに加えて
/// シェーダー段の資源合計の上限を持つのは、同じ画素段が他のセットのバッファ・影の画像も一緒に消費し、
/// 表の枚数がその合計側で先に頭打ちになるためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct ディスクリプタ索引上限 {
    /// maxPerStageDescriptorSampledImages。
    シェーダー段あたりの画像ディスクリプタ数: u32,
    /// maxDescriptorSetSampledImages。
    セットあたりの画像ディスクリプタ数: u32,
    /// maxPerStageResources。1つのシェーダー段が全種別あわせて参照できる資源の数であり、描画先の添付も数える。
    シェーダー段あたりの資源合計数: u32,
}

impl ディスクリプタ索引上限 {
    pub(crate) fn 生成する(
        シェーダー段あたりの画像ディスクリプタ数: u32,
        セットあたりの画像ディスクリプタ数: u32,
        シェーダー段あたりの資源合計数: u32,
    ) -> Self {
        Self {
            シェーダー段あたりの画像ディスクリプタ数,
            セットあたりの画像ディスクリプタ数,
            シェーダー段あたりの資源合計数,
        }
    }

    pub(crate) fn シェーダー段あたりの画像ディスクリプタ数(self) -> u32 {
        self.シェーダー段あたりの画像ディスクリプタ数
    }

    pub(crate) fn セットあたりの画像ディスクリプタ数(self) -> u32 {
        self.セットあたりの画像ディスクリプタ数
    }

    pub(crate) fn シェーダー段あたりの資源合計数(self) -> u32 {
        self.シェーダー段あたりの資源合計数
    }
}
