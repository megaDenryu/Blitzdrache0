//! 遠方環境の照明資源の生成局面。呼ばれるのはレンダラー生成時の1回だけであり、以降のフレームは束縛を参照して
//! 中身を焼き直すだけである。途中で失敗したら、それまでに作った資源をその場で逆順に片付ける。
//!
//! 受け取るのは大気のベイク済み画像から借りる束縛先と4本のシェーダー、返すのは組み上がった一式である。
//! 解像度をここで既定値から決めるのは、遠方環境と3つの派生表現の解像度が互いに噛み合う組でなければならず
//! (鏡面畳込みの最詳細段は遠方環境と同じ一辺で、複製がビット単位で成り立つ)、外から個別に差し込ませないためである。

use ash::vk;

use super::bake_record::焼き始めの記録;
use super::遠方環境の照明資源;
use crate::atmosphere::遠方環境の解像度;
use crate::distant_environment::derived::{反射率積分表の解像度, 拡散照度の解像度, 鏡面畳込みの解像度};
use crate::distant_environment::遠方環境のシェーダー一式;
use crate::error::レンダラーエラー;
use crate::vulkan::derived_environment::{派生表現のシェーダー一式, 派生表現の解像度一式, 派生表現一式};
use crate::vulkan::distant_environment::{遠方環境が借りる束縛先, 遠方環境一式};
use crate::vulkan::tracked_device::GPUデバイス;

pub(super) fn 生成する(
    device: &GPUデバイス,
    メモリプロパティ: &vk::PhysicalDeviceMemoryProperties,
    借りる束縛先: 遠方環境が借りる束縛先<'_>,
    シェーダー: &遠方環境のシェーダー一式,
) -> Result<遠方環境の照明資源, レンダラーエラー> {
    let 遠方環境 = 遠方環境一式::生成する(device, メモリプロパティ, 遠方環境の解像度::既定値(), 借りる束縛先, &シェーダー.遠方環境)?;
    let 派生 = 派生表現一式::生成する(
        device,
        メモリプロパティ,
        既定の解像度一式(),
        遠方環境.画像入力を作る().ビュー,
        &派生表現のシェーダー一式 {
            拡散照度: &シェーダー.拡散照度,
            鏡面畳込み: &シェーダー.鏡面畳込み,
            反射率積分表: &シェーダー.反射率積分表,
        },
    );
    match 派生 {
        Ok(派生表現) => Ok(遠方環境の照明資源 {
            遠方環境,
            派生表現,
            焼き始め: 焼き始めの記録::新規(),
        }),
        Err(誤り) => {
            遠方環境.破棄する(device);
            Err(誤り)
        }
    }
}

fn 既定の解像度一式() -> 派生表現の解像度一式 {
    派生表現の解像度一式 {
        拡散照度: 拡散照度の解像度::既定値(),
        鏡面畳込み: 鏡面畳込みの解像度::既定値(),
        反射率積分表: 反射率積分表の解像度::既定値(),
    }
}
