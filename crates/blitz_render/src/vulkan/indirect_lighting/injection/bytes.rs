//! 解析入力を、3つの画像がそれぞれ読むバイト並びへ詰める工程。受け取るのは解析入力と焼いた画像の解像度、
//! 返すのは画像1枚ぶんのバイト列である。触れる状態を持たない。
//!
//! バイト並びをここが単独で持つのは、これがCPUの宣言とGPUの画素形式の間の唯一の契約だからである。
//! 立方体は段が最も外、次に層(面)、その中を縦・横の順に並べる。転送は段ごとに1つの領域を持ち、
//! 1つの領域の中は層が連続するというVulkanの規約に合わせてある。
//!
//! 第4成分に0を詰めるのは、派生表現の生成シェーダーが予約として0を書くのに合わせるためである。

use crate::atmosphere::遠方環境の解像度;
use crate::distant_environment::derived::{反射率積分表の解像度, 拡散照度の解像度, 鏡面畳込みの解像度};
use crate::distant_environment::{遠方環境の焼かせる解析入力, 遠方環境の解析入力, 鏡面畳込みの解析入力};
use crate::numeric::half_precision::単精度を半精度へ;

/// 立方体の面の数。層番号はこの数だけ並ぶ。
const 面数: usize = 6;

pub(super) fn 拡散照度のバイト列(入力: &遠方環境の解析入力, 解像度: 拡散照度の解像度) -> Vec<u8> {
    let テクセル数 = 解像度.面の一辺().全テクセル数();
    let mut バイト列 = Vec::with_capacity(テクセル数 * 8);
    for _ in 0..テクセル数 {
        四成分を詰める(&mut バイト列, 入力.拡散照度());
    }
    バイト列
}

/// 段ごとに1つの領域を作る前提で、段番号の昇順に並べる。1つの段の中は層番号の昇順である。
pub(super) fn 鏡面畳込みのバイト列(入力: &遠方環境の解析入力, 解像度: 鏡面畳込みの解像度) -> Vec<u8> {
    let mut バイト列 = Vec::new();
    for 段 in 解像度.全段() {
        let 面のテクセル数 = 解像度.段の一辺(段).面のテクセル数();
        for 面番号 in 0..面数 {
            let 色 = 段と面の色(入力, 段.番号(), 面番号);
            for _ in 0..面のテクセル数 {
                四成分を詰める(&mut バイト列, 色);
            }
        }
    }
    バイト列
}

pub(super) fn 反射率積分表のバイト列(表の2成分: [f32; 2], 解像度: 反射率積分表の解像度) -> Vec<u8> {
    let テクセル数 = 解像度.全テクセル数();
    let mut バイト列 = Vec::with_capacity(テクセル数 * 4);
    for _ in 0..テクセル数 {
        for 成分 in 表の2成分 {
            バイト列.extend_from_slice(&単精度を半精度へ(成分).to_le_bytes());
        }
    }
    バイト列
}

/// 遠方環境の立方体画像を一様な放射輝度で埋める。並びは面(層番号の順)が最も外、次に縦、横が最も速い。
pub(super) fn 遠方環境のバイト列(入力: &遠方環境の焼かせる解析入力, 解像度: 遠方環境の解像度) -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(解像度.全テクセル数() * 8);
    for _ in 0..解像度.全テクセル数() {
        四成分を詰める(&mut バイト列, 入力.一様な放射輝度());
    }
    バイト列
}

fn 段と面の色(入力: &遠方環境の解析入力, 段番号: u32, 面番号: usize) -> [f32; 3] {
    match 入力.鏡面畳込み() {
        鏡面畳込みの解析入力::段ごとの一様な色(色一覧) => {
            let 添字 = usize::try_from(段番号).unwrap_or(usize::MAX);
            *色一覧
                .get(添字)
                .unwrap_or_else(|| panic!("段{段番号}の色が解析入力に無い(段数の一致は注入の入口が確かめている)"))
        }
        鏡面畳込みの解析入力::面ごとの一様な色(色一覧) => 色一覧[面番号],
    }
}

fn 四成分を詰める(バイト列: &mut Vec<u8>, 色: [f32; 3]) {
    for 成分 in [色[0], 色[1], 色[2], 0.0] {
        バイト列.extend_from_slice(&単精度を半精度へ(成分).to_le_bytes());
    }
}
