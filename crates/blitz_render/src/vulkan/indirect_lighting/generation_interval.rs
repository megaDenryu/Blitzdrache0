//! 間接照明の生成の合計をGPU計器の1区間として立てる宣言。担当するのは「どのパスの和をどの名前で出すか」だけである。
//!
//! 分位の加法性は一般に成立しないため、区間ごとの窓から採ったp50を足した値は1フレームの生成合計のp50ではない。
//! 全更新費用は合計そのものの分位で語る必要があり、そのためにはフレーム内で先に足した1標本を窓へ入れるしかない(参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」)。
//!
//! この宣言を計器(`vulkan::gpu_timing`)でなくここに置くのは、計器を描画の内容から独立に保つためである。
//! 計器は宣言を受け取って適用するだけであり、間接照明という機能を1つも知らない。
//! 足す4つのパス名はここから見える定数そのものを読むため、名前の綴りをこのファイルが二重に持つことはない。
//!
//! 反射率積分表生成を含めないのは、焼き直しの条件が違うためである。
//! 表は起動後の1回で焼き終わり、遠方環境キーが変わるたびの更新には現れない。
//! 表を足すと初回のフレームだけ合計が跳ね、更新1回の費用を言わなくなる。

use crate::vulkan::derived_environment::{copy_pass, pass as 派生パス};
use crate::vulkan::distant_environment::pass as 遠方環境パス;
use crate::vulkan::gpu_timing::合成区間の宣言;

/// GPU計器の区間名。全更新費用はこの区間の分位で語る。
pub(crate) const 生成の合計のパス名: &str = "間接照明生成の合計";

/// 遠方環境キーが変わったフレームに積まれる生成パスの和。
/// 鏡面畳込みは粗さの段ごとにパスを積むが、計器が同名の回をフレーム内で足すため、この一覧では1つの名前で全縮小段を代表する。
pub(crate) fn 合成区間を宣言する() -> 合成区間の宣言 {
    合成区間の宣言::生成する(
        生成の合計のパス名,
        vec![
            遠方環境パス::遠方環境生成のパス名,
            copy_pass::最詳細段の複製のパス名,
            派生パス::拡散照度生成のパス名,
            派生パス::鏡面畳込み生成のパス名,
        ],
    )
}
