//! そのフレームの転送の材料を、注入した枝から選び出す操作。触れるのは`注入`と`派生表現`の2つだけである。
//!
//! 2つの`Option`へ分けて返すのは、レンダーグラフの積み上げが枝ごとに別のパスを積むためである。判別共用体のまま
//! 渡すと、積む側が枝を開き直すことになる。どちらか一方だけが`Some`になることは、注入の資源が判別共用体である
//! ことから保たれる。

use super::injection::検収の注入;
use super::{焼かせる注入, 解析入力の注入, 遠方環境の照明資源};

impl 遠方環境の照明資源 {
    pub(super) fn 派生表現へ直に与える注入を作る(&self) -> Option<解析入力の注入> {
        match &self.注入 {
            Some(検収の注入::派生表現へ直に与える(資源)) => Some(資源.転送の材料を作る(&self.派生表現)),
            Some(検収の注入::遠方環境へ与えて焼かせる(_)) | None => None,
        }
    }

    pub(super) fn 遠方環境へ与える注入を作る(&self) -> Option<焼かせる注入> {
        match &self.注入 {
            Some(検収の注入::遠方環境へ与えて焼かせる(資源)) => Some(資源.転送の材料を作る(&self.派生表現)),
            Some(検収の注入::派生表現へ直に与える(_)) | None => None,
        }
    }
}
