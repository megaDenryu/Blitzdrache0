//! 間接照明の表現を焼くパス1フレームぶんの入力。担当するのは「グラフへ登録する4枚の画像と、そのフレームで
//! 積むパスの束縛資源を、名前で取り違えずに1つへまとめて運ぶ」ことである。
//!
//! 焼く組を判別共用体にするのは、遠方環境と拡散照度と鏡面畳込みが同じ条件で一緒に焼き直されるためである。
//! 3つを別々の`Option`にすると、遠方環境だけを焼いて拡散照度を古いまま残すという、型の上でだけ成立して
//! 絵の上では成立しない組を作れてしまう。
//!
//! 反射率積分表だけを外へ出すのは、大気にも時刻にも依らず起動後の1回だけ焼くためであり、焼き直しの条件が
//! 他の3つと違うからである(参照: `_doc/設計/放射輝度問い合わせ階層.md`「遠方環境の形式と生成(3-Ia)」)。

use ash::vk;

use super::{焼かせる注入, 解析入力の注入};
use crate::distant_environment::input::遠方環境の生成指示;
use crate::vulkan::atmosphere_lut::大気のベイク済み画像の生成入力;
use crate::vulkan::derived_environment::派生表現の生成入力;
use crate::vulkan::distant_environment::{遠方環境の即時定数, 遠方環境の生成入力};
use crate::vulkan::sync::フレームスロット添字;

/// 描画入力を組むのに要る、遠方環境の照明資源の外から来る材料。引数の列が伸び続けるのを避けて1つに束ねる。
pub(crate) struct 描画入力の材料 {
    pub(crate) フレーム添字: フレームスロット添字,
    pub(crate) 即時定数: 遠方環境の即時定数,
    pub(crate) 指示: 遠方環境の生成指示,
    /// 遠方環境用スカイビューを焼く先の画像と束縛。大気のベイク済み画像一式が所有するため外から渡す。
    pub(crate) 遠方環境用スカイビューの画像: 登録する画像,
    pub(crate) 遠方環境用スカイビューの生成入力: 大気のベイク済み画像の生成入力,
}

/// グラフへ登録する画像1枚ぶんの値。
pub(crate) struct 登録する画像 {
    pub(crate) 画像: vk::Image,
    pub(crate) ビュー: vk::ImageView,
    pub(crate) 寸法: vk::Extent2D,
}

/// 遠方環境用スカイビューをそのフレームで焼くときの、登録する画像と生成パス1本ぶんの束縛。
/// 画像を焼くフレームだけ運ぶのは、誰も参照しない画像をグラフへ登録しないためである。
pub(crate) struct 遠方環境用スカイビューの焼き上げ {
    pub(crate) 画像: 登録する画像,
    pub(crate) 生成入力: 大気のベイク済み画像の生成入力,
}

/// そのフレームで焼く4つの組。1つも焼かないフレームは画像も登録しない。
///
/// 枝の大きさの差(`焼く`が264バイト、`何も焼かない`が0バイト)を許すのは、この値がフレームごとに1つだけ
/// スタックへ載り、配列にもコレクションにも入らないためである。差の出どころは遠方環境用スカイビューの
/// 即時定数であり、空中遠近と枝を共有する型のため使わない枝のぶんまで場所を取る。clippyが勧める`Box`は、
/// 200バイトほどのスタックを節約する代わりに毎フレームのヒープ確保を1回増やすため採らない
/// (参照: `_doc/設計/性能アーキテクチャ方針.md`「日常の性能規律」)。
#[allow(clippy::large_enum_variant)]
pub(crate) enum 間接照明の焼く組 {
    /// 遠方環境キーが前フレームと同じである。遠方環境・拡散照度・鏡面畳込みのパスを1本も積まない。
    何も焼かない,
    /// 遠方環境を焼き直し、その結果から拡散照度と鏡面畳込みを導き直す。
    /// 鏡面畳込みの一覧は計算で焼く段だけであり、最詳細段は遠方環境からの複製で作るため含まない。
    焼く {
        /// 検収が遠方環境へ中身を注入する実行では`None`である。その実行の遠方環境は転送で埋まり、表を読まない。
        遠方環境用スカイビュー: Option<遠方環境用スカイビューの焼き上げ>,
        遠方環境: 遠方環境の生成入力,
        拡散照度: 派生表現の生成入力,
        鏡面畳込み一覧: Vec<派生表現の生成入力>,
    },
}

/// 1フレームぶんの間接照明の描画入力。
pub(crate) struct 間接照明の描画入力 {
    pub(crate) 遠方環境の画像: 登録する画像,
    pub(crate) 拡散照度の画像: 登録する画像,
    pub(crate) 鏡面畳込みの画像: 登録する画像,
    pub(crate) 反射率積分表の画像: 登録する画像,
    /// 最詳細段の複製が写す1層ぶんの範囲。遠方環境と鏡面畳込みの最詳細段は同じ一辺を持つ。
    pub(crate) 遠方環境の範囲: vk::Extent3D,
    pub(crate) 層数: u32,
    pub(crate) 焼く組: 間接照明の焼く組,
    /// まだ1度も焼いていないフレームだけ値を持つ。以降のフレームは焼き直さない。
    pub(crate) 反射率積分表の入力: Option<派生表現の生成入力>,
    /// 検収が派生表現へ直に解析入力を注入した実行だけ値を持つ。値があるフレームは3つの画像を転送で埋め、生成パスを積まない。
    pub(crate) 注入: Option<解析入力の注入>,
    /// 検収が遠方環境へ解析入力を注入した実行だけ値を持つ。値があるフレームは遠方環境の生成パスを転送へ差し替え、
    /// 反射率積分表も転送で埋める。拡散照度と鏡面畳込みは生成側が焼く。
    pub(crate) 焼かせる注入: Option<焼かせる注入>,
}
