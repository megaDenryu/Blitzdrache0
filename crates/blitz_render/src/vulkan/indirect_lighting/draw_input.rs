//! 遠方環境の照明資源から、そのフレームの描画入力を組み立てる操作。触れるのは遠方環境一式・派生表現一式・
//! 焼き始めの記録の3つだけであり、どれもこの型が所有する。呼び出し規律は「コマンドを記録して送信すると決めた
//! フレームで1度だけ呼ぶ」ことであり、見送るフレームでは呼ばない(焼き始めの記録が実際に焼いた事実とずれるため)。

use super::inputs::{登録する画像, 間接照明の描画入力, 間接照明の焼く組};
use super::遠方環境の照明資源;
use crate::distant_environment::input::遠方環境の生成指示;
use crate::vulkan::derived_environment::派生表現の生成入力;
use crate::vulkan::distant_environment::遠方環境の即時定数;
use crate::vulkan::sync::フレームスロット添字;

impl 遠方環境の照明資源 {
    /// そのフレームの描画入力。積むパスの本数は段の展開側が実際に積んだものから数えるため、ここでは返さない。
    pub(crate) fn 描画入力を作る(
        &mut self,
        フレーム添字: フレームスロット添字,
        即時定数: 遠方環境の即時定数,
        指示: 遠方環境の生成指示,
    ) -> 間接照明の描画入力 {
        let 計画 = self.焼き始め.計画を決める(指示);
        let 焼く組 = if 計画.遠方環境を焼く {
            間接照明の焼く組::焼く {
                遠方環境: self.遠方環境.生成入力を作る(フレーム添字, 即時定数),
                拡散照度: self.派生表現.拡散照度の生成入力(),
                鏡面畳込み一覧: self.計算で焼く段の入力一覧(),
            }
        } else {
            間接照明の焼く組::何も焼かない
        };
        let 遠方環境 = self.遠方環境.画像入力を作る();
        間接照明の描画入力 {
            遠方環境の画像: 登録する画像 {
                画像: 遠方環境.画像,
                ビュー: 遠方環境.ビュー,
                寸法: 遠方環境.グラフへ渡す寸法,
            },
            拡散照度の画像: 立方体の登録する画像(self.派生表現.拡散照度画像()),
            鏡面畳込みの画像: 立方体の登録する画像(self.派生表現.鏡面畳込み画像()),
            反射率積分表の画像: self.反射率積分表の登録する画像(),
            遠方環境の範囲: 遠方環境.範囲,
            層数: 遠方環境.層数,
            焼く組,
            反射率積分表の入力: 計画.反射率積分表を焼く.then(|| self.派生表現.反射率積分表の生成入力()),
        }
    }

    /// 計算で焼く段だけの生成入力。最詳細段は遠方環境からの複製で作るため含まない。
    fn 計算で焼く段の入力一覧(&self) -> Vec<派生表現の生成入力> {
        self.派生表現
            .鏡面畳込みの解像度()
            .全段()
            .into_iter()
            .filter(|段| 段.番号() > 0)
            .map(|段| self.派生表現.鏡面畳込みの生成入力(段))
            .collect()
    }

    fn 反射率積分表の登録する画像(&self) -> 登録する画像 {
        let 表 = self.派生表現.反射率積分表の画像();
        登録する画像 {
            画像: 表.画像,
            ビュー: 表.ビュー,
            寸法: 表.グラフへ渡す寸法(),
        }
    }
}

/// 立方体の派生画像は全段を含む立方体ビューで登録する。段ごとの書き込み先のビューは生成入力が持つ。
fn 立方体の登録する画像(画像: &crate::vulkan::derived_environment::派生の立方体画像) -> 登録する画像 {
    登録する画像 {
        画像: 画像.画像,
        ビュー: 画像.立方体ビュー,
        寸法: 画像.グラフへ渡す寸法(),
    }
}
