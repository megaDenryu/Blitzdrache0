//! 遠方環境の照明資源から、そのフレームの描画入力を組み立てる操作。触れるのは遠方環境一式・派生表現一式・
//! 焼き始めの記録の3つだけであり、どれもこの型が所有する。呼び出し規律は「コマンドを記録して送信すると決めた
//! フレームで1度だけ呼ぶ」ことであり、見送るフレームでは呼ばない(焼き始めの記録が実際に焼いた事実とずれるため)。

use super::injection::検収の注入;
use super::inputs::{
    描画入力の材料, 登録する画像, 遠方環境用スカイビューの焼き上げ, 間接照明の描画入力, 間接照明の焼く組
};
use super::遠方環境の照明資源;
use crate::indirect_lighting::焼き上げの計画;
use crate::vulkan::derived_environment::派生表現の生成入力;

impl 遠方環境の照明資源 {
    /// そのフレームの描画入力。焼く組も反射率積分表の入力も1つの計画から作る。計画そのものを入力へ載せないのは、
    /// 積んだパスの本数を段の展開が積んだ枝で数えるためである(計画を渡すと本数の転記へ戻る道が残る)。
    pub(crate) fn 描画入力を作る(&mut self, 材料: 描画入力の材料) -> 間接照明の描画入力 {
        let 粗さ段数 = self.派生表現.鏡面畳込みの解像度().粗さ段数();
        let 計画 = match &self.注入 {
            Some(検収の注入::派生表現へ直に与える(_)) => 焼き上げの計画::何も焼かない(粗さ段数),
            Some(検収の注入::遠方環境へ与えて焼かせる(_)) => {
                焼き上げの計画::遠方環境から派生だけを焼く(粗さ段数)
            }
            None => self.焼き始め.計画を決める(材料.指示, 粗さ段数),
        };
        let 焼く組 = if 計画.遠方環境を焼くか() {
            間接照明の焼く組::焼く {
                遠方環境用スカイビュー: 計画.遠方環境用スカイビューを焼くか().then_some(
                    遠方環境用スカイビューの焼き上げ {
                        画像: 材料.遠方環境用スカイビューの画像,
                        生成入力: 材料.遠方環境用スカイビューの生成入力,
                    },
                ),
                遠方環境: self.遠方環境.生成入力を作る(材料.フレーム添字, 材料.即時定数),
                拡散照度: self.派生表現.拡散照度の生成入力(),
                鏡面畳込み一覧: self.計算で焼く段の入力一覧(計画),
            }
        } else {
            間接照明の焼く組::何も焼かない
        };
        let 遠方環境 = self.遠方環境.画像入力を作る();
        間接照明の描画入力 {
            遠方環境の画像: 登録する画像 {
                画像: 遠方環境.画像,
                ビュー: 遠方環境.ビュー,
                寸法: 遠方環境.グラフへ渡す寸法,
            },
            拡散照度の画像: 立方体の登録する画像(self.派生表現.拡散照度画像()),
            鏡面畳込みの画像: 立方体の登録する画像(self.派生表現.鏡面畳込み画像()),
            反射率積分表の画像: self.反射率積分表の登録する画像(),
            遠方環境の範囲: 遠方環境.範囲,
            層数: 遠方環境.層数,
            焼く組,
            反射率積分表の入力: 計画.反射率積分表を焼くか().then(|| self.派生表現.反射率積分表の生成入力()),
            注入: self.派生表現へ直に与える注入を作る(),
            焼かせる注入: self.遠方環境へ与える注入を作る(),
        }
    }

    /// 計算で焼く段だけの生成入力。最詳細段は遠方環境からの複製で作るため含まない。
    ///
    /// 注意: 並びの長さは計画が答える段数と必ず等しい。等しくないと、焼く段の構成そのものが計画とずれる。
    /// 破れたら段の構成の導出が2つに割れていることを意味する。
    fn 計算で焼く段の入力一覧(&self, 計画: 焼き上げの計画) -> Vec<派生表現の生成入力> {
        let 一覧 = self.計算で焼く段を集める();
        let 段数 = u32::try_from(一覧.len()).unwrap_or_else(|_| panic!("計算で焼く鏡面の段数がu32に収まらない"));
        assert_eq!(段数, 計画.計算で焼く鏡面の段数(), "積む鏡面の段数が計画の段数と一致しない");
        一覧
    }

    fn 計算で焼く段を集める(&self) -> Vec<派生表現の生成入力> {
        self.派生表現
            .鏡面畳込みの解像度()
            .全段()
            .into_iter()
            .filter(|段| 段.番号() > 0)
            .map(|段| self.派生表現.鏡面畳込みの生成入力(段))
            .collect()
    }

    fn 反射率積分表の登録する画像(&self) -> 登録する画像 {
        let 表 = self.派生表現.反射率積分表の画像();
        登録する画像 {
            画像: 表.画像,
            ビュー: 表.ビュー,
            寸法: 表.グラフへ渡す寸法(),
        }
    }
}

/// 立方体の派生画像は全段を含む立方体ビューで登録する。段ごとの書き込み先のビューは生成入力が持つ。
fn 立方体の登録する画像(画像: &crate::vulkan::derived_environment::派生の立方体画像) -> 登録する画像 {
    登録する画像 {
        画像: 画像.画像,
        ビュー: 画像.立方体ビュー,
        寸法: 画像.グラフへ渡す寸法(),
    }
}
