//! 1つの灯の1つの面が描く対象を絞る判定。触れるのは灯の位置と影響半径と面の錐台の3つだけであり、
//! 描画発行の中身にも資源にも触れない。
//!
//! 絞る順は、灯の影響半径の球で落としてから面の錐台で分ける形である。半径の外側は減衰の窓が0になり
//! 寄与そのものが消えるため、そこにある遮蔽を記録しても絵に出ない。錐台の判定を先に置くと、
//! 半径の外にある遠くの対象を6面ぶん判定することになる(参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断n」)。
//!
//! どちらの判定も保守的である。落としてはならない対象を落とすと、その場所だけ影が抜ける。

use blitz_math::{メートル, ワールド, 位置};

use crate::clustered_lighting::影響半径;
use crate::cube_image::立方体の面;
use crate::point_light_shadow::面の錐台;

/// 1つの灯の1つの面ぶんの絞り。
///
/// 前提: 灯の位置は描く対象と同じカメラ大域原点で狭めた値である。原点が違うと、絞った候補と描く位置が食い違う。
#[derive(Debug, Clone, Copy)]
pub(crate) struct 面ごとの絞り {
    灯の位置: 位置<ワールド>,
    影響半径: 影響半径,
    錐台: 面の錐台,
}

impl 面ごとの絞り {
    pub(crate) fn 生成する(灯の位置: 位置<ワールド>, 影響半径: 影響半径, 面: 立方体の面) -> Self {
        Self {
            灯の位置,
            影響半径,
            錐台: 面の錐台::灯の位置と面から生成する(灯の位置, 面),
        }
    }

    /// その球がこの面へ影を落としうるか。
    pub(crate) fn 球が候補か(self, 中心: 位置<ワールド>, 半径: メートル) -> bool {
        if !self.影響半径の球と交わるか(中心, 半径) {
            return false;
        }
        self.錐台.球と交わるか(中心, 半径)
    }

    fn 影響半径の球と交わるか(self, 中心: 位置<ワールド>, 半径: メートル) -> bool {
        let 差 = [
            中心.x().値() - self.灯の位置.x().値(),
            中心.y().値() - self.灯の位置.y().値(),
            中心.z().値() - self.灯の位置.z().値(),
        ];
        let 距離の二乗 = 差[0] * 差[0] + 差[1] * 差[1] + 差[2] * 差[2];
        let 届く距離 = self.影響半径.長さ().値() + 半径.値();
        距離の二乗 <= 届く距離 * 届く距離
    }
}
