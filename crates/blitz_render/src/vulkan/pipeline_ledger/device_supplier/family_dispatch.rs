//! 族とキーの組み合わせから、どのパイプライン生成の工程を呼ぶかを決める工程。受け取るのは供給元とキー1つ、返すのは生成したVkPipelineである。
//!
//! 組み合わせを網羅の`match`で書き切るのは、族とキーが食い違う組み合わせを型付きの失敗として1つ残らず塞ぐためである。
//! ワイルドカードで塞ぐと、枝が増えたときに新しい食い違いが黙って「不一致」へ落ち、どの組み合わせが未対応なのか差分に現れない。

use ash::vk;

use super::{デバイスパイプライン供給元, 材質描画族};
use crate::error::{パイプライン台帳エラー, レンダラーエラー};
use crate::vulkan::pipeline_ledger::key::パイプラインキー;

pub(super) fn 生成する(
    供給元: &デバイスパイプライン供給元<'_>, キー: パイプラインキー
) -> Result<vk::Pipeline, レンダラーエラー> {
    match (供給元.族, キー) {
        (材質描画族::シーン, パイプラインキー::シーン { 描画先, 深度状態, .. }) => {
            let Some(カラー形式) = 描画先.カラー形式() else {
                return Err(パイプライン台帳エラー::色の無い描画先でシーンを描く { 記述: キー.記述() }.into());
            };
            let layout = 供給元.レイアウト.シーン();
            let 標本数 = 描画先.標本数();
            供給元
                .生成係
                .シーンのpipelineを生成する(カラー形式, 描画先.深度形式(), 標本数, layout, 深度状態)
        }
        (材質描画族::シャドウ, パイプラインキー::シャドウ { 描画先 }) => {
            let layout = 供給元.レイアウト.シャドウ();
            供給元.生成係.シャドウのpipelineを生成する(描画先.深度形式(), 描画先.標本数(), layout)
        }
        // レイアウトが色パスと同じものであることが、同じプッシュ定数と同じディスクリプタセットで描く根拠である。
        (材質描画族::深度プリパス, パイプラインキー::深度プリパス { 描画先, .. }) => {
            let layout = 供給元.レイアウト.シーン();
            供給元.生成係.深度プリパスのpipelineを生成する(描画先.深度形式(), 描画先.標本数(), layout)
        }
        (材質描画族::シーン, パイプラインキー::シャドウ { .. } | パイプラインキー::深度プリパス { .. })
        | (材質描画族::シャドウ, パイプラインキー::シーン { .. } | パイプラインキー::深度プリパス { .. })
        | (材質描画族::深度プリパス, パイプラインキー::シーン { .. } | パイプラインキー::シャドウ { .. }) => {
            Err(供給元.族の不一致(キー))
        }
    }
}
