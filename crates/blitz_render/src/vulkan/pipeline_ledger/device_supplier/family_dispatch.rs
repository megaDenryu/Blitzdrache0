//! 族とキーの組み合わせから、どのパイプライン生成の工程を呼ぶかを決める工程。受け取るのは供給元とキー1つ、返すのは生成したVkPipelineである。
//!
//! 組み合わせを網羅の`match`で書き切るのは、族とキーが食い違う組み合わせを型付きの失敗として1つ残らず塞ぐためである。
//! ワイルドカードで塞ぐと、枝が増えたときに新しい食い違いが黙って「不一致」へ落ち、どの組み合わせが未対応なのか差分に現れない。
//!
//! シーンと深度プリパスがキーの材質変種で画素段を選び分けるのは、変種ごとに別の画素段を持つためである。深度プリパスは
//! 画素段を1つも積まないが、同じ変種の`シェーダー一式`から作ることで色パスと同じ頂点段のSPIR-Vを使う根拠を保つ。

use ash::vk;

use super::{デバイスパイプライン供給元, 材質描画族のシェーダー};
use crate::error::{パイプライン台帳エラー, レンダラーエラー};
use crate::vulkan::pipeline::材質描画族のパイプラインの生成係;
use crate::vulkan::pipeline_ledger::key::パイプラインキー;

pub(super) fn 生成する(
    供給元: &デバイスパイプライン供給元<'_>, キー: パイプラインキー
) -> Result<vk::Pipeline, レンダラーエラー> {
    match (供給元.族(), キー) {
        (
            材質描画族のシェーダー::シーン(画素段),
            パイプラインキー::シーン {
                描画先, 材質変種, 深度状態,
            ..
            },
        ) => {
            let Some(カラー形式) = 描画先.カラー形式() else {
                return Err(パイプライン台帳エラー::色の無い描画先でシーンを描く { 記述: キー.記述() }.into());
            };
            let 生成係 = 材質描画族のパイプラインの生成係::生成する(供給元.確保係(), 画素段.材質変種で選ぶ(材質変種));
            生成係.シーンのパイプラインを生成する(
                カラー形式,
                描画先.深度形式(),
                描画先.標本数(),
                供給元.レイアウト().シーン(),
                深度状態,
            )
        }
        (材質描画族のシェーダー::シャドウ(シェーダー), パイプラインキー::シャドウ { 描画先 }) => {
            let 生成係 = 材質描画族のパイプラインの生成係::生成する(供給元.確保係(), シェーダー);
            生成係.シャドウのパイプラインを生成する(描画先.深度形式(), 描画先.標本数(), 供給元.レイアウト().シャドウ())
        }
        // レイアウトが色パスと同じものであることが、同じプッシュ定数と同じディスクリプタセットで描く根拠である。
        (材質描画族のシェーダー::深度プリパス(画素段), パイプラインキー::深度プリパス { 描画先, 材質変種 }) =>
        {
            let 生成係 = 材質描画族のパイプラインの生成係::生成する(供給元.確保係(), 画素段.材質変種で選ぶ(材質変種));
            生成係.深度プリパスのパイプラインを生成する(描画先.深度形式(), 描画先.標本数(), 供給元.レイアウト().シーン())
        }
        (材質描画族のシェーダー::シーン(_), パイプラインキー::シャドウ { .. } | パイプラインキー::深度プリパス { .. })
        | (材質描画族のシェーダー::シャドウ(_), パイプラインキー::シーン { .. } | パイプラインキー::深度プリパス { .. })
        | (材質描画族のシェーダー::深度プリパス(_), パイプラインキー::シーン { .. } | パイプラインキー::シャドウ { .. }) => {
            Err(供給元.族の不一致(キー))
        }
    }
}
