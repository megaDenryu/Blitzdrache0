//! 1本のVkPipelineを一意に選ぶキー。担当するのは、実際にパイプライン生成入力へ効く軸だけを枝と成分に持つことである。
//!
//! 注意: 材質IDをキーへ混ぜてはならない。材質ごとにパイプラインを作ると、係数だけが違う材質でPSOが増える。
//! 材質は係数とテクスチャスロットの違いであり、描画発行の並べ替えではキーの次の第2鍵として扱う。
//! 静的なメッシュとスキン済みのメッシュを別の枝にしないのは、スキニングパスの出力が同じ頂点レイアウトを持ち、
//! 頂点入力の宣言が一致するためである。パスで枝を分けるのは、シャドウが材質も照明問い合わせも読まないからである
//! (参照: `_doc/設計/マルチマテリアルと材質境界.md`「材質の3軸」)。
//!
//! 注意: `深度プリパス`は現在の生成(`device_supplier::family_dispatch`)がこの成分を1つも読んでいない。材質変種が1つしか無く、
//! その固定機能が深度プリパスの固定機能と一致しているためである。**変種を増やすときは、増やす側がこの枝の扱いを決めなければならない。**
//! 決め方は2つしかない。増えた変種の固定機能(面の向き・塗り方・深度バイアス等)を深度プリパスの生成へも反映するか、
//! その変種を深度プリパスの対象外にするかである。どちらもせずに変種を増やすと、色パスと固定機能の違うパイプラインで
//! 深度を書くことになり、色パスの深度比較を等値にできる根拠が黙って崩れる
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「IIa-1の実装」)。

use super::lighting_binding_layout::照明束縛レイアウト;
use super::render_target::描画先の一意化;
use crate::vulkan::material_variant::材質変種キー;
use crate::vulkan::pipeline::色パスの深度状態;

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub(crate) enum パイプラインキー {
    シーン {
        描画先: 描画先の一意化,
        材質変種: 材質変種キー,
        照明束縛: 照明束縛レイアウト,
        深度状態: 色パスの深度状態, // 深度の比べ方と書き込みの有無。深度プリパス方式が選ぶ軸であり、パイプライン生成入力を実際に変えるため成分に持つ
    },
    深度プリパス {
        描画先: 描画先の一意化,
        材質変種: 材質変種キー, // 面の向きや塗り方が変種で変わりうるため持つ。照明束縛を持たないのは画素段が無く照明問い合わせのセットを1つも読まないため
    },
    シャドウ {
        描画先: 描画先の一意化,
    }, // 距離区分ごとに別のパイプラインにしないのは、区分の違いがライトビュー射影とプッシュ定数だけであり、パイプライン生成入力を1つも変えないため
}

impl パイプラインキー {
    /// 失敗の表示で使う記述。キーの中身をそのまま並べる。
    pub(crate) fn 記述(self) -> String {
        format!("{self:?}")
    }
}
