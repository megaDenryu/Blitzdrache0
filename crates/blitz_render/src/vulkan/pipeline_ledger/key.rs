//! 1本のVkPipelineを一意に選ぶキー。担当するのは、実際にパイプライン生成入力へ効く軸だけを枝と成分に持つことである。
//!
//! 注意: 材質IDをキーへ混ぜてはならない。材質ごとにパイプラインを作ると、係数だけが違う材質でPSOが増える。
//! 材質は係数とテクスチャスロットの違いであり、描画発行の並べ替えではキーの次の第2鍵として扱う。
//! 静的なメッシュとスキン済みのメッシュを別の枝にしないのは、スキニングパスの出力が同じ頂点レイアウトを持ち、
//! 頂点入力の宣言が一致するためである。パスで枝を分けるのは、シャドウが材質も照明問い合わせも読まないからである
//! (参照: `_doc/設計/マルチマテリアルと材質境界.md`「材質の3軸」)。

use super::lighting_binding_layout::照明束縛レイアウト;
use super::render_target::描画先の一意化;
use crate::vulkan::material_variant::材質変種キー;

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub(crate) enum パイプラインキー {
    シーン {
        描画先: 描画先の一意化,
        材質変種: 材質変種キー,
        照明束縛: 照明束縛レイアウト,
    },
    /// 距離区分ごとに別のパイプラインにしないのは、区分の違いがライトビュー射影とプッシュ定数だけであり、
    /// パイプライン生成入力を1つも変えないためである。
    シャドウ { 描画先: 描画先の一意化 },
}

impl パイプラインキー {
    /// 失敗の表示で使う記述。キーの中身をそのまま並べる。
    pub(crate) fn 記述(self) -> String {
        format!("{self:?}")
    }
}
