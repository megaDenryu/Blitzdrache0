//! 3つの族の表を1度で作り切る工程。受け取るのはデバイス・レイアウト・シェーダー束・台帳の成分、返すのは3つの表である。
//!
//! 1つでも失敗したら、その呼び出しで作った表だけを逆順に破棄して何も返さない。部分的にできた組を呼び出し元へ渡さないためである。
//! 供給元がレイアウトを借りるだけなのは、構築が終わった時点で台帳がレイアウトを所有できるようにするためである。
//!
//! シーンと深度プリパスが同じ`材質変種別の画素段`を受け取ることが、両者が同じ頂点段のSPIR-Vから作られることの実装である。

use ash::vk;

use crate::error::レンダラーエラー;
use crate::shader_bundle::シェーダー束;
use crate::vulkan::allocator::GPU資源の確保係;
use crate::vulkan::pipeline::色パスの深度状態;

use super::create::台帳の成分;
use super::device_supplier::{デバイスパイプライン供給元, パイプラインを破棄する, 材質描画族のシェーダー};
use super::entry_table::パイプライン記載表;
use super::layouts::材質描画族のレイアウト;
use super::required_keys;

pub(super) type 三族の表 = (
    パイプライン記載表<vk::Pipeline>,
    パイプライン記載表<vk::Pipeline>,
    パイプライン記載表<vk::Pipeline>,
);

pub(super) fn 三族の表を構築する(
    確保係: &GPU資源の確保係<'_>,
    レイアウト: &材質描画族のレイアウト,
    シェーダー: &シェーダー束,
    成分: &台帳の成分,
) -> Result<三族の表, レンダラーエラー> {
    let device = 確保係.論理デバイス();
    let シーンの画素段 = シェーダー.シーン.束縛レイアウトで選ぶ(成分.シーンの照明束縛);
    let mut シーン供給元 = デバイスパイプライン供給元::生成する(確保係, 材質描画族のシェーダー::シーン(シーンの画素段), レイアウト);
    let シーンのキー一覧 = required_keys::シーンのキー一覧(
        成分.シーンの描画先,
        成分.シーンの照明束縛,
        色パスの深度状態::方式から決める(成分.深度プリパス方式),
    );
    let mut シーン = パイプライン記載表::構築する(&mut シーン供給元, &シーンのキー一覧)?;

    let mut シャドウ供給元 =
        デバイスパイプライン供給元::生成する(確保係, 材質描画族のシェーダー::シャドウ(&シェーダー.シャドウ), レイアウト);
    let mut シャドウ = match パイプライン記載表::構築する(&mut シャドウ供給元, &required_keys::シャドウのキー一覧(成分.シャドウの描画先))
    {
        Ok(表) => 表,
        Err(誤り) => {
            シーン.破棄する(|pipeline| パイプラインを破棄する(device, pipeline));
            return Err(誤り);
        }
    };

    let mut プリパス供給元 =
        デバイスパイプライン供給元::生成する(確保係, 材質描画族のシェーダー::深度プリパス(シーンの画素段), レイアウト);
    let プリパスのキー一覧 = required_keys::深度プリパスのキー一覧(成分.深度プリパスの描画先);
    match パイプライン記載表::構築する(&mut プリパス供給元, &プリパスのキー一覧) {
        Ok(深度プリパス) => Ok((シーン, シャドウ, 深度プリパス)),
        Err(誤り) => {
            シャドウ.破棄する(|pipeline| パイプラインを破棄する(device, pipeline));
            シーン.破棄する(|pipeline| パイプラインを破棄する(device, pipeline));
            Err(誤り)
        }
    }
}
