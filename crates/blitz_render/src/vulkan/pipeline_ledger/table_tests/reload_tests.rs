//! シェーダーの差し替えの取引の状態遷移の検査。構築と待機のどちらで失敗しても、台帳の中身が呼び出し前のままであり、
//! その呼び出しで作った実体が1つ残らず捨てられることを見る。
//!
//! GPUの実物に依らないのは、取引の順序と後始末が供給元の向こう側を知らないためである。実デバイスの待機を失敗させる
//! 故障注入は入れていない(注入点を本番の待機経路へ置くことになる)。

use super::{シーンのキー, シーンの描画先, 数える供給元};
use crate::error::レンダラーエラー;
use crate::vulkan::pipeline_ledger::entry_table::パイプライン記載表;
use crate::vulkan::pipeline_ledger::reload::差し替えを行う;

fn 待機の失敗() -> レンダラーエラー {
    レンダラーエラー::粒子入力不一致
}

#[test]
fn 待機が通れば新表へ入れ替えて旧表だけを捨てる() {
    let mut 供給元 = 数える供給元::常に成功する();
    let キー一覧 = [シーンのキー(シーンの描画先())];
    let mut 現在 = パイプライン記載表::構築する(&mut 供給元, &キー一覧).unwrap();
    差し替えを行う(&mut 現在, &mut 供給元, &キー一覧, || Ok(())).unwrap();
    assert_eq!(*現在.引く(キー一覧[0]).unwrap(), 2, "新しく作った実体へ入れ替わっていない");
    assert_eq!(供給元.破棄した実体, vec![1], "旧表の実体だけを1回捨てていない");
}

#[test]
fn 待機が失敗したら新表だけを捨てて旧表を残す() {
    let mut 供給元 = 数える供給元::常に成功する();
    let キー一覧 = [シーンのキー(シーンの描画先())];
    let mut 現在 = パイプライン記載表::構築する(&mut 供給元, &キー一覧).unwrap();
    let 結果 = 差し替えを行う(&mut 現在, &mut 供給元, &キー一覧, || Err(待機の失敗()));
    assert!(結果.is_err(), "待機の失敗が呼び出し元へ返っていない");
    assert_eq!(*現在.引く(キー一覧[0]).unwrap(), 1, "待機の失敗で台帳の中身が変わった");
    assert_eq!(供給元.破棄した実体, vec![2], "待機の失敗で作りかけの新表が捨てられていない");
}

#[test]
fn 構築が失敗したら待機を掛けず旧表を残す() {
    let mut 供給元 = 数える供給元::常に成功する();
    let キー一覧 = [シーンのキー(シーンの描画先())];
    let mut 現在 = パイプライン記載表::構築する(&mut 供給元, &キー一覧).unwrap();
    let mut 落ちる供給元 = 数える供給元::指定回で失敗する(1);
    let mut 待機を掛けたか = false;
    let 結果 = 差し替えを行う(&mut 現在, &mut 落ちる供給元, &キー一覧, || {
        待機を掛けたか = true;
        Ok(())
    });
    assert!(結果.is_err(), "構築の失敗が呼び出し元へ返っていない");
    assert!(!待機を掛けたか, "構築が失敗したのにGPUの待機を掛けた");
    assert_eq!(*現在.引く(キー一覧[0]).unwrap(), 1, "構築の失敗で台帳の中身が変わった");
    assert!(供給元.破棄した実体.is_empty(), "構築の失敗で旧表の実体が捨てられた");
}
