//! パイプラインキーそのものの性質の検査。同じ材料から常に同じキーが出ること、順序と等値が食い違わないこと、
//! 描画先やパス種別が違えば別のキーになることを見る。
//!
//! 順序と等値の整合を見るのは、キーが描画発行の並べ替えの第1鍵だからである。`Ord`が`Eq`と食い違うと、
//! 等しいキーの発行が離れて並び、パイプラインの切替が減らない。

use std::cmp::Ordering;

use super::{シャドウのキー, シーンのキー, シーンの描画先, 別の描画先};

#[test]
fn 同じ材料からは常に同じキーが出る() {
    assert_eq!(シーンのキー(シーンの描画先()), シーンのキー(シーンの描画先()));
    assert_eq!(シャドウのキー(), シャドウのキー());
}

#[test]
fn 描画先が違えば別のキーになる() {
    assert_ne!(シーンのキー(シーンの描画先()), シーンのキー(別の描画先()));
}

#[test]
fn パス種別が違えば別のキーになる() {
    assert_ne!(シーンのキー(シーンの描画先()), シャドウのキー());
}

#[test]
fn 順序と等値が食い違わない() {
    let 全キー = [シーンのキー(シーンの描画先()), シーンのキー(別の描画先()), シャドウのキー()];
    for 左 in 全キー {
        for 右 in 全キー {
            let 等しいか = 左 == 右;
            assert_eq!(等しいか, 左.cmp(&右) == Ordering::Equal, "等値と順序が食い違う: {左:?} と {右:?}");
        }
    }
}

#[test]
fn 順序は全順序である() {
    let 全キー = [シーンのキー(シーンの描画先()), シーンのキー(別の描画先()), シャドウのキー()];
    for 左 in 全キー {
        for 右 in 全キー {
            assert_eq!(左.cmp(&右).reverse(), 右.cmp(&左), "順序が反対称でない");
        }
    }
    let mut 並び = 全キー;
    並び.sort_unstable();
    let mut 逆から = 全キー;
    逆から.reverse();
    逆から.sort_unstable();
    assert_eq!(並び, 逆から, "入力の並びで整列の結果が変わった");
}
