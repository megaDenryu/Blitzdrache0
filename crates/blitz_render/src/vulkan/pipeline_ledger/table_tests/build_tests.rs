//! 表の構築・参照・破棄の検査。生成が1キーにつき1回であること、同じキーが同じ実体を返すこと、
//! 構築の途中で失敗したら作りかけだけをちょうど1回ずつ破棄して何も返さないこと、未知のキーを型付きで拒むことを見る。

use super::{シャドウのキー, シーンのキー, シーンの描画先, 別の描画先, 数える供給元};
use crate::vulkan::pipeline_ledger::entry_table::パイプライン記載表;

#[test]
fn 必要キー集合ぶんだけ生成し同じキーは同じ実体を返す() {
    let mut 供給元 = 数える供給元::常に成功する();
    let キー一覧 = [シーンのキー(シーンの描画先()), シャドウのキー()];
    let 表 = パイプライン記載表::構築する(&mut 供給元, &キー一覧).unwrap();
    assert_eq!(供給元.生成回数, 2, "キーの数と生成回数が一致しない");
    assert_eq!(表.記載数(), 2);
    let 一度目 = *表.引く(キー一覧[0]).unwrap();
    let 二度目 = *表.引く(キー一覧[0]).unwrap();
    assert_eq!(一度目, 二度目, "同じキーが別の実体を返した");
}

#[test]
fn 別のキーは別の実体を返す() {
    let mut 供給元 = 数える供給元::常に成功する();
    let キー一覧 = [シーンのキー(シーンの描画先()), シーンのキー(別の描画先())];
    let 表 = パイプライン記載表::構築する(&mut 供給元, &キー一覧).unwrap();
    assert_ne!(表.引く(キー一覧[0]).unwrap(), 表.引く(キー一覧[1]).unwrap());
}

#[test]
fn 未知のキーは型付きで拒む() {
    let mut 供給元 = 数える供給元::常に成功する();
    let 表 = パイプライン記載表::構築する(&mut 供給元, &[シーンのキー(シーンの描画先())]).unwrap();
    let 誤り = 表.引く(シャドウのキー()).unwrap_err();
    assert!(誤り.to_string().contains("台帳に無い"), "未知のキーの失敗の文言が違う: {誤り}");
}

#[test]
fn 同じキーを2回数え上げたら拒む() {
    let mut 供給元 = 数える供給元::常に成功する();
    let キー = シーンのキー(シーンの描画先());
    let 誤り = パイプライン記載表::構築する(&mut 供給元, &[キー, キー]).unwrap_err();
    assert!(誤り.to_string().contains("2回現れた"), "重複の失敗の文言が違う: {誤り}");
    assert_eq!(供給元.破棄した実体, vec![1], "重複を見つけたのに先に作った実体を捨てていない");
}

#[test]
fn 構築の途中で失敗したら作りかけだけを1回ずつ捨てて何も返さない() {
    let mut 供給元 = 数える供給元::指定回で失敗する(3);
    let キー一覧 = [シーンのキー(シーンの描画先()), シーンのキー(別の描画先()), シャドウのキー()];
    assert!(パイプライン記載表::構築する(&mut 供給元, &キー一覧).is_err());
    assert_eq!(供給元.破棄した実体, vec![1, 2], "作りかけの破棄が1回ずつでない");
}

#[test]
fn 構築が失敗しても先に作った表は生き続ける() {
    let mut 旧供給元 = 数える供給元::常に成功する();
    let キー = シーンのキー(シーンの描画先());
    let 旧表 = パイプライン記載表::構築する(&mut 旧供給元, &[キー]).unwrap();
    let mut 新供給元 = 数える供給元::指定回で失敗する(1);
    assert!(パイプライン記載表::構築する(&mut 新供給元, &[キー]).is_err());
    assert_eq!(*旧表.引く(キー).unwrap(), 1, "新表の構築の失敗が旧表を壊した");
    assert!(旧供給元.破棄した実体.is_empty(), "旧表の実体が捨てられた");
}

#[test]
fn 破棄は記載を1回ずつ捨てて空にする() {
    let mut 供給元 = 数える供給元::常に成功する();
    let キー一覧 = [シーンのキー(シーンの描画先()), シャドウのキー()];
    let mut 表 = パイプライン記載表::構築する(&mut 供給元, &キー一覧).unwrap();
    let mut 捨てた = Vec::new();
    表.破棄する(|実体| 捨てた.push(実体));
    assert_eq!(捨てた, vec![1, 2]);
    assert_eq!(表.記載数(), 0, "破棄した表に記載が残った");
    表.破棄する(|実体| 捨てた.push(実体));
    assert_eq!(捨てた, vec![1, 2], "2回目の破棄が同じ実体をもう一度捨てた");
}
