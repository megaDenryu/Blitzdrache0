//! シェーダーの差し替えでシーンのパイプラインを入れ替える取引。担当するのは、構築と待機と交換の3つの局面のどこで失敗しても、
//! 台帳が壊れず、その呼び出しで作ったパイプラインが1本も残らないようにすることである。
//!
//! 待機を呼び出し元から関数で受け取るのは、GPUの全作業完了を待てるのはGPU環境を所有するレンダラーだけであり、
//! 台帳がデバイスの待機を自分では行わないためである。関数で受け取ると、取引の順序と後始末を台帳の側に閉じられる。
//! 注意: 待機の失敗で新表をそのまま落としてはならない。記載表が持つのは生のVkPipelineであり、Rustの値として落ちても
//! GPUの資源は解放されない。待機が失敗した局面では、旧表を残したまま新表だけを明示的に破棄する。
//! シャドウの表を触らないのは、シーンのシェーダーだけを差し替えるホットリロードだからである
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段6)。
//!
//! 深度プリパスの表を一緒に差し替えるのは、その表がシーンと同じ頂点段のSPIR-Vから作られているためである。
//! シーンだけを差し替えると、色パスが新しい頂点段、深度プリパスが旧い頂点段で描く状態になり、両者が同じ位置を出す根拠が消える。
//! 新しいプリパスの表を先に作るのは、待機を1度だけに保つためである。待機を通ったシーンの差し替えの後で表を入れ替えれば、
//! 旧い表をGPUが使い終わっていることの根拠はシーンの側と同じものになる。
//!
//! 受け取るのが契約別の束であるのは、画素段のエントリが契約ごとに分かれているためである。1組の頂点段と画素段だけを
//! 受け取る形にすると、定数近似の画素段が遠方環境のパイプラインへ載る組み合わせを呼び出し側が作れてしまう。
//! レイアウトが上位互換であるため構築も束縛も成功し、間接光だけが無言で黒へ落ちる。束から1組を選ぶ鍵は台帳が
//! 生成時から持つ照明束縛レイアウトであり、呼び出し元は選択に関与しない。

use crate::error::レンダラーエラー;
use crate::indirect_lighting::契約別の描画シェーダー;
use crate::vulkan::pipeline::色パスの深度状態;

use super::device_supplier::{デバイスパイプライン供給元, 材質描画族};
use super::entry_table::パイプライン記載表;
use super::key::パイプラインキー;
use super::required_keys;
use super::supplier::パイプライン供給元;
use super::材質描画族パイプライン台帳;

impl 材質描画族パイプライン台帳 {
    /// 新しいシェーダーで全シーンキーの表を作り、`待つ`が成功したときにだけ交換して旧表を破棄する。
    /// 構築が失敗しても待機が失敗しても、台帳の中身は呼び出し前のままである。
    /// レイアウトは族で共有しており作り直さないため、交換してもディスクリプタセットの束縛の互換性は変わらない。
    pub(crate) fn シーンを差し替える(
        &mut self,
        device: &ash::Device,
        シェーダー: &契約別の描画シェーダー,
        待つ: impl FnOnce() -> Result<(), レンダラーエラー>,
    ) -> Result<(), レンダラーエラー> {
        let キー一覧 = required_keys::シーンのキー一覧(
            self.シーンの描画先,
            self.シーンの照明束縛,
            色パスの深度状態::方式から決める(self.深度プリパス方式),
        );
        let 選んだ一式 = シェーダー.束縛レイアウトで選ぶ(self.シーンの照明束縛);
        let mut プリパス供給元 =
            デバイスパイプライン供給元::生成する(device, 材質描画族::深度プリパス, &self.レイアウト, 選んだ一式);
        let プリパスのキー一覧 = required_keys::深度プリパスのキー一覧(self.深度プリパスの描画先);
        let mut 新プリパス = パイプライン記載表::構築する(&mut プリパス供給元, &プリパスのキー一覧)?;
        let mut シーン供給元 = デバイスパイプライン供給元::生成する(device, 材質描画族::シーン, &self.レイアウト, 選んだ一式);
        if let Err(誤り) = 差し替えを行う(&mut self.シーン, &mut シーン供給元, &キー一覧, 待つ) {
            新プリパス.破棄する(|実体| プリパス供給元.破棄する(実体));
            return Err(誤り);
        }
        let mut 旧プリパス = std::mem::replace(&mut self.深度プリパス, 新プリパス);
        旧プリパス.破棄する(|実体| プリパス供給元.破棄する(実体));
        Ok(())
    }
}

/// 取引の順序と後始末。GPUの実物に依らないため、検査用の供給元で状態遷移をそのまま確かめられる。
///
/// 待機を構築より後に置くのは、構築の失敗で待機を掛けないためである。待機はフレームの進行を止める操作であり、
/// シェーダーのコンパイルが通らなかっただけの差し替えで掛けると、失敗するたびに描画が1フレーム止まる。
pub(super) fn 差し替えを行う<実体, 供給元>(
    現在: &mut パイプライン記載表<実体>,
    供給元: &mut 供給元,
    キー一覧: &[パイプラインキー],
    待つ: impl FnOnce() -> Result<(), レンダラーエラー>,
) -> Result<(), レンダラーエラー>
where
    供給元: パイプライン供給元<実体 = 実体>,
{
    let mut 新表 = パイプライン記載表::構築する(供給元, キー一覧)?;
    if let Err(誤り) = 待つ() {
        新表.破棄する(|実体| 供給元.破棄する(実体));
        return Err(誤り);
    }
    let mut 旧表 = std::mem::replace(現在, 新表);
    旧表.破棄する(|実体| 供給元.破棄する(実体));
    Ok(())
}
