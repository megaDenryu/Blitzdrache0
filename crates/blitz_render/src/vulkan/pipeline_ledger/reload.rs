//! シェーダーの差し替えでシーンのパイプラインを入れ替える取引。担当するのは、この入れ替えを
//! 「新表を先に構築する」「交換して旧表を破棄する」の2つの局面に分け、途中で失敗しても台帳が壊れないようにすることである。
//!
//! 2つに分けるのは、その間にGPUの全作業完了の待機が挟まるためである。待機を持つのはGPU環境を所有するレンダラーであり、
//! 台帳はデバイスの待機を自分では行わない。構築が失敗した場合は交換の局面へ進まないため、旧表がそのまま生き続ける。
//! シャドウの表を触らないのは、シーンのシェーダーだけを差し替えるホットリロードだからである
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段6)。

use ash::vk;

use crate::error::レンダラーエラー;
use crate::shader_set::シェーダー一式;

use super::device_supplier::{pipelineを破棄する, デバイスパイプライン供給元, 材質描画族};
use super::entry_table::パイプライン記載表;
use super::required_keys;
use super::材質描画族パイプライン台帳;

/// 構築だけが済んで、まだ台帳へ入っていないシーンの表。交換の局面へ渡すためだけの値である。
pub(crate) struct 差し替え用のシーン表 {
    表: パイプライン記載表<vk::Pipeline>,
}

impl 材質描画族パイプライン台帳 {
    /// 台帳を1つも変えずに、新しいシェーダーで全シーンキーの表を作る。失敗したら作りかけを自分で片付けて`Err`を返す。
    pub(crate) fn シーンの新表を構築する(
        &self,
        device: &ash::Device,
        シェーダー: &シェーダー一式,
    ) -> Result<差し替え用のシーン表, レンダラーエラー> {
        let mut 供給元 = デバイスパイプライン供給元::生成する(device, 材質描画族::シーン, &self.レイアウト, シェーダー);
        let キー一覧 = required_keys::シーンのキー一覧(self.シーンの描画先, self.シーンの照明問い合わせ);
        let 表 = パイプライン記載表::構築する(&mut 供給元, &キー一覧)?;
        Ok(差し替え用のシーン表 { 表 })
    }

    /// 前提: 呼び出し元がGPUの全作業完了を待ってから呼ぶ。旧いシーンのパイプラインをGPUが読んでいる最中に破棄しないためである。
    /// レイアウトは族で共有しており作り直さないため、交換してもディスクリプタセットの束縛の互換性は変わらない。
    pub(crate) fn シーンの表を交換する(&mut self, device: &ash::Device, 新表: 差し替え用のシーン表) {
        let mut 旧表 = std::mem::replace(&mut self.シーン, 新表.表);
        旧表.破棄する(|pipeline| pipelineを破棄する(device, pipeline));
    }
}
