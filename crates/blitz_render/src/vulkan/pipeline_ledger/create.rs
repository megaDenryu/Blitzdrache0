//! パイプライン台帳の生成の局面。呼ばれるのはレンダラー生成時の1回だけであり、以降のフレームは参照しかしない。
//!
//! ここで必要キー集合を全部作り切ることが「記録中にlazy生成しない」の実装である。途中で失敗したら、その呼び出しで
//! 作ったパイプラインとレイアウトを逆順に破棄して何も返さない。部分的にできた台帳を呼び出し元から見せない。
//!
//! 深度プリパスの表を方式によらず作るのは、積むかどうかがフレームの組み立て方の選択であり、パイプラインの有無をそこへ連動させると
//! 積まない方式で「未知のキー」と「作っていないキー」が同じ失敗に見えるためである。作るのは材質変種の数ぶんの1本だけである。

use ash::vk;

use crate::error::レンダラーエラー;
use crate::frame_composition::深度プリパス方式;
use crate::shader_bundle::シェーダー束;
use crate::vulkan::allocator::GPU資源の確保係;
use crate::vulkan::depth::深度形式;
use crate::vulkan::descriptor::シーンセットレイアウト一式;
use crate::vulkan::pipeline::描画の標本数;
use crate::vulkan::shadow_map::シャドウマップ形式;

use super::build_tables::{三族の表, 三族の表を構築する};
use super::layouts::材質描画族のレイアウト;
use super::lighting_binding_layout::照明束縛レイアウト;
use super::render_target::描画先の一意化;
use super::材質描画族パイプライン台帳;

impl 材質描画族パイプライン台帳 {
    /// `シーンカラー形式`はシーン段階の色添付の形式である(ポスト処理があればHDR中間画像、無ければスワップチェーン)。
    pub(crate) fn 生成する(
        確保係: &GPU資源の確保係<'_>,
        セット: &シーンセットレイアウト一式,
        シーンカラー形式: vk::Format,
        シェーダー: &シェーダー束,
        方式: 深度プリパス方式,
    ) -> Result<Self, レンダラーエラー> {
        let device = 確保係.論理デバイス();
        let レイアウト = 材質描画族のレイアウト::生成する(確保係, セット)?;
        let 成分 = 台帳の成分 {
            シーンの描画先: 描画先の一意化::色と深度へ描く(シーンカラー形式, 深度形式, 描画の標本数),
            シーンの照明束縛: セット.照明束縛(),
            深度プリパス方式: 方式,
            シャドウの描画先: 描画先の一意化::深度だけへ描く(シャドウマップ形式, 描画の標本数),
            深度プリパスの描画先: 描画先の一意化::深度だけへ描く(深度形式, 描画の標本数),
        };
        match 三族の表を構築する(確保係, &レイアウト, シェーダー, &成分) {
            Ok(表) => Ok(成分.台帳へ組み上げる(レイアウト, 表)),
            Err(誤り) => {
                レイアウト.破棄する(device);
                Err(誤り)
            }
        }
    }
}

/// 表を作る前に決まる台帳の成分。表の構築と台帳の組み上げの両方が同じ値を読むため、1つの型で運ぶ。
pub(super) struct 台帳の成分 {
    pub(super) シーンの描画先: 描画先の一意化,
    pub(super) シーンの照明束縛: 照明束縛レイアウト,
    pub(super) 深度プリパス方式: 深度プリパス方式,
    pub(super) シャドウの描画先: 描画先の一意化,
    pub(super) 深度プリパスの描画先: 描画先の一意化,
}

impl 台帳の成分 {
    fn 台帳へ組み上げる(
        self, レイアウト: 材質描画族のレイアウト, 表: 三族の表
    ) -> 材質描画族パイプライン台帳 {
        let (シーン, シャドウ, 深度プリパス) = 表;
        材質描画族パイプライン台帳 {
            レイアウト,
            シーンの描画先: self.シーンの描画先,
            シーンの照明束縛: self.シーンの照明束縛,
            深度プリパス方式: self.深度プリパス方式,
            シャドウの描画先: self.シャドウの描画先,
            深度プリパスの描画先: self.深度プリパスの描画先,
            シーン,
            シャドウ,
            深度プリパス,
        }
    }
}
