//! パイプライン台帳の生成の局面。呼ばれるのはレンダラー生成時の1回だけであり、以降のフレームは参照しかしない。
//!
//! ここで必要キー集合を全部作り切ることが「記録中にlazy生成しない」の実装である。途中で失敗したら、その呼び出しで
//! 作ったパイプラインとレイアウトを逆順に破棄して何も返さない。部分的にできた台帳を呼び出し元から見せない。

use ash::vk;

use crate::error::レンダラーエラー;
use crate::shader_bundle::シェーダー束;
use crate::vulkan::depth::深度形式;
use crate::vulkan::descriptor::シーンセットレイアウト一式;
use crate::vulkan::pipeline::描画の標本数;
use crate::vulkan::shadow_map::シャドウマップ形式;

use super::device_supplier::{デバイスパイプライン供給元, 材質描画族};
use super::entry_table::パイプライン記載表;
use super::layouts::材質描画族のレイアウト;
use super::lighting_binding_layout::照明束縛レイアウト;
use super::render_target::描画先の一意化;
use super::required_keys;
use super::材質描画族パイプライン台帳;

impl 材質描画族パイプライン台帳 {
    /// `シーンカラー形式`はシーン段階の色添付の形式である(ポスト処理があればHDR中間画像、無ければスワップチェーン)。
    pub(crate) fn 生成する(
        device: &ash::Device,
        セット: &シーンセットレイアウト一式,
        シーンカラー形式: vk::Format,
        シェーダー: &シェーダー束,
    ) -> Result<Self, レンダラーエラー> {
        let レイアウト = 材質描画族のレイアウト::生成する(device, セット)?;
        let シーンの描画先 = 描画先の一意化::色と深度へ描く(シーンカラー形式, 深度形式, 描画の標本数);
        let シャドウの描画先 = 描画先の一意化::深度だけへ描く(シャドウマップ形式, 描画の標本数);
        let シーンの照明束縛 = セット.照明束縛();
        let 表 = 両族の表を構築する(device, &レイアウト, シェーダー, シーンの描画先, シーンの照明束縛, シャドウの描画先);
        match 表 {
            Ok((シーン, シャドウ)) => Ok(Self {
                レイアウト,
                シーンの描画先,
                シーンの照明束縛,
                シャドウの描画先,
                シーン,
                シャドウ,
            }),
            Err(誤り) => {
                レイアウト.破棄する(device);
                Err(誤り)
            }
        }
    }
}

type 両族の表 = (パイプライン記載表<vk::Pipeline>, パイプライン記載表<vk::Pipeline>);

/// 供給元はレイアウトを借りるだけであり、構築が終わったところで手放す。台帳がレイアウトを所有できるようにするためである。
fn 両族の表を構築する(
    device: &ash::Device,
    レイアウト: &材質描画族のレイアウト,
    シェーダー: &シェーダー束,
    シーンの描画先: 描画先の一意化,
    シーンの照明束縛: 照明束縛レイアウト,
    シャドウの描画先: 描画先の一意化,
) -> Result<両族の表, レンダラーエラー> {
    let mut シーン供給元 = デバイスパイプライン供給元::生成する(
        device,
        材質描画族::シーン,
        レイアウト,
        シェーダー.シーン.束縛レイアウトで選ぶ(シーンの照明束縛),
    );
    let mut シーン =
        パイプライン記載表::構築する(&mut シーン供給元, &required_keys::シーンのキー一覧(シーンの描画先, シーンの照明束縛))?;
    let mut シャドウ供給元 = デバイスパイプライン供給元::生成する(device, 材質描画族::シャドウ, レイアウト, &シェーダー.シャドウ);
    match パイプライン記載表::構築する(&mut シャドウ供給元, &required_keys::シャドウのキー一覧(シャドウの描画先))
    {
        Ok(シャドウ) => Ok((シーン, シャドウ)),
        Err(誤り) => {
            シーン.破棄する(|pipeline| super::device_supplier::pipelineを破棄する(device, pipeline));
            Err(誤り)
        }
    }
}
