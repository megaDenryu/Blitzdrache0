//! キーとパイプライン実体の対応表の構築・参照・破棄。担当するのは、必要キー集合を1度で完全に構築して原子的に返すことと、
//! 同じキーが同じ実体を返し生成が1回であることを保つことである。
//!
//! 注意: 記録中に足してはならない(lazy生成の禁止)。1本でも構築に失敗したら、その呼び出しで作った実体だけを破棄して
//! 何も返さない。呼び出し元が持つ旧い表はこの関数が触らないため、失敗しても旧い表がそのまま使える。
//! 走査が線形なのは、記載の数がパス種別と材質変種の積であり、両手で数えられる桁に収まるためである。連想表を使わないのは、
//! 反復順が実行ごとに揺れる余地を作らないためでもある。
//! 参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段6

use crate::error::{パイプライン台帳エラー, レンダラーエラー};

use super::key::パイプラインキー;
use super::supplier::パイプライン供給元;

#[derive(Debug)]
pub(super) struct パイプライン記載表<実体> {
    記載: Vec<(パイプラインキー, 実体)>,
}

impl<実体> パイプライン記載表<実体> {
    /// 必要キー集合を受け取り、全部そろった表だけを返す。同じキーが2回現れるのは呼び出し元が数え上げを誤った状態であり、
    /// 通すと同じキーの実体が2つできて破棄も2回になるため型付きで拒む。
    pub(super) fn 構築する<供給元>(
        供給元: &mut 供給元, キー一覧: &[パイプラインキー]
    ) -> Result<Self, レンダラーエラー>
    where
        供給元: パイプライン供給元<実体 = 実体>,
    {
        let mut 表 = Self {
            記載: Vec::with_capacity(キー一覧.len()),
        };
        for キー in キー一覧 {
            let 結果 = if 表.記載.iter().any(|(登録, _)| 登録 == キー) {
                Err(レンダラーエラー::from(パイプライン台帳エラー::キーの重複 {
                    記述: キー.記述(),
                }))
            } else {
                供給元.生成する(*キー)
            };
            match 結果 {
                Ok(実体) => 表.記載.push((*キー, 実体)),
                Err(誤り) => {
                    表.破棄する(|実体| 供給元.破棄する(実体));
                    return Err(誤り);
                }
            }
        }
        Ok(表)
    }

    /// 未知のキーを型付きで失敗させる。記録中に作る枝を持たないことが、lazy生成をしないことの実装である。
    pub(super) fn 引く(&self, キー: パイプラインキー) -> Result<&実体, レンダラーエラー> {
        let Some((_, 実体)) = self.記載.iter().find(|(登録, _)| *登録 == キー) else {
            return Err(パイプライン台帳エラー::未知のキー { 記述: キー.記述() }.into());
        };
        Ok(実体)
    }

    /// 前提: この表の実体をGPUが使っていないことを呼び出し元が保証する。1つの実体を2回渡さないため、所有権ごと取り出す。
    pub(super) fn 破棄する(&mut self, mut 捨てる: impl FnMut(実体)) {
        for (_, 実体) in self.記載.drain(..) {
            捨てる(実体);
        }
    }

    /// 生成回数と記載数が一致することの検査だけが読む。
    #[cfg(test)]
    pub(super) fn 記載数(&self) -> usize {
        self.記載.len()
    }
}
