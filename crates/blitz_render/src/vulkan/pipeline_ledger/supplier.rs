//! パイプラインキー1つから実体を作り、要らなくなった実体を捨てる供給元の契約。
//!
//! 台帳の状態遷移(完全構築・原子的な公開・失敗時の巻き戻し・破棄の1回)をGPUの実物なしで検査できるようにするため、
//! 実体の作り方をこのトレイトへ出す。台帳そのものはVkPipelineという型を知らない。

use crate::error::レンダラーエラー;

use super::key::パイプラインキー;

pub(super) trait パイプライン供給元 {
    type 実体;

    fn 生成する(&mut self, キー: パイプラインキー) -> Result<Self::実体, レンダラーエラー>;

    /// 前提: 呼び出し元がGPUの使用完了を保証してから渡す。
    fn 破棄する(&mut self, 実体: Self::実体);
}
