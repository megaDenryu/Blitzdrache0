//! 台帳が自分の持つ成分からパイプラインキーを組み立てる操作。触れるのは描画先の一意化・照明束縛レイアウト・深度プリパス方式の3つだけであり、
//! 表そのものには触れない。
//!
//! 不変条件は、ここが組み立てるキーが起動時に数え上げた必要キー集合(`required_keys`)と1つ残らず一致することである。
//! 一致しないキーを組み立てると、記録の途中で未知のキーとして失敗する。組み立てを台帳の内側へ閉じるのは、呼び出し元が
//! 描画先や契約の成分を持ち回らずに済むようにするためである。

use crate::vulkan::material_variant::材質変種キー;
use crate::vulkan::pipeline::色パスの深度状態;

use super::key::パイプラインキー;
use super::材質描画族パイプライン台帳;

impl 材質描画族パイプライン台帳 {
    /// その材質変種を描くシーンパイプラインのキー。描画先と照明の契約は台帳が持つため、呼び出し元は変種だけを渡す。
    pub(crate) fn シーンのキー(&self, 材質変種: 材質変種キー) -> パイプラインキー {
        パイプラインキー::シーン {
            描画先: self.シーンの描画先,
            材質変種,
            照明束縛: self.シーンの照明束縛,
            深度状態: 色パスの深度状態::方式から決める(self.深度プリパス方式),
        }
    }

    /// その材質変種を深度プリパスで描くパイプラインのキー。色パスと同じ変種を渡すのは、両者の固定機能が同じであることの表れである。
    pub(crate) fn 深度プリパスのキー(&self, 材質変種: 材質変種キー) -> パイプラインキー {
        パイプラインキー::深度プリパス {
            描画先: self.深度プリパスの描画先,
            材質変種,
        }
    }

    pub(crate) fn シャドウのキー(&self) -> パイプラインキー {
        パイプラインキー::シャドウ {
            描画先: self.シャドウの描画先,
        }
    }
}
