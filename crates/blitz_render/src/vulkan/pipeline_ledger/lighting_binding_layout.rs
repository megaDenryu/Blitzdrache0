//! シーン描画のパイプラインが束縛する照明資源のレイアウトと、そこで呼ぶシェーダー関数の組の識別子。
//! パイプラインキーの1軸であり、担当するのは「実在するレイアウトと関数の組を型の枝として表す」ことである。
//!
//! 世界が選ぶ`照明問い合わせ契約`と別の型である。あちらは世界の間接照明方針から起動時に1つ選ばれる方針の側であり、
//! こちらは選ばれた結果としてパイプラインが束縛する現物の識別子である。1つの契約から複数のパイプラインが作られ、
//! そのすべてが同じレイアウトを束縛するため、キーの軸としては契約と別の名前で持つ。
//!
//! 生の能力ビットや空のtagを先行させないのは、枝が1つしかない段階でそれを作ると、GPU側にもCPU側にも
//! 意味の無い分岐が残るためである。順5のクラスタが入るときに枝を足す
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「照明問い合わせ資源のGPU境界」)。

use crate::indirect_lighting::照明問い合わせ契約;

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub(crate) enum 照明束縛レイアウト {
    /// ヘッダ・方向光レコード列・局所光レコード列・多段影の1組を読むレイアウト。間接光は定数近似の係数だけである。
    直接光と多段影,
    /// 上の4つに加えて拡散照度の立方体画像・鏡面畳込みの立方体画像・反射率積分表を読むレイアウト。
    直接光と多段影と遠方環境,
}

impl 照明束縛レイアウト {
    /// 世界が選んだ契約から、パイプラインが束縛する現物を決める。写す向きが1つなのは、契約が方針の側だからである。
    pub(crate) fn 契約から選ぶ(契約: 照明問い合わせ契約) -> Self {
        match 契約 {
            照明問い合わせ契約::定数近似 => Self::直接光と多段影,
            照明問い合わせ契約::遠方環境LambertGGX => Self::直接光と多段影と遠方環境,
        }
    }

    /// 遠方環境の3つの画像をセットへ結ぶか。レイアウトが宣言した束縛先を1つも空のまま残さないための判定である。
    pub(crate) fn 遠方環境の画像を結ぶか(self) -> bool {
        match self {
            Self::直接光と多段影 => false,
            Self::直接光と多段影と遠方環境 => true,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 定数近似の契約は遠方環境の画像を結ばない() {
        let レイアウト = 照明束縛レイアウト::契約から選ぶ(照明問い合わせ契約::定数近似);
        assert_eq!(レイアウト, 照明束縛レイアウト::直接光と多段影);
        assert!(!レイアウト.遠方環境の画像を結ぶか());
    }

    #[test]
    fn 遠方環境の契約は遠方環境の画像を結ぶ() {
        let レイアウト = 照明束縛レイアウト::契約から選ぶ(照明問い合わせ契約::遠方環境LambertGGX);
        assert_eq!(レイアウト, 照明束縛レイアウト::直接光と多段影と遠方環境);
        assert!(レイアウト.遠方環境の画像を結ぶか());
    }
}
