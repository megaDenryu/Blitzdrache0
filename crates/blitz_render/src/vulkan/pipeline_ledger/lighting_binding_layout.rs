//! パイプラインキーの1軸であり、担当するのは「実在するレイアウトと関数の組を型の枝として表す」ことである。
//!
//! 世界が選ぶ`照明問い合わせ契約`と別の型である。あちらは世界の間接照明方針から起動時に1つ選ばれる方針の側であり、
//! こちらは選ばれた結果としてパイプラインが束縛する現物の識別子である。1つの契約から複数のパイプラインが作られ、
//! そのすべてが同じレイアウトを束縛するため、キーの軸としては契約と別の名前で持つ。
//!
//! 生の能力ビットや空のtagを先行させないのは、枝が1つしかない段階でそれを作ると、GPU側にもCPU側にも
//! 意味の無い分岐が残るためである。順3のIBLや順5のクラスタが入るときに枝を足す
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「照明問い合わせ資源のGPU境界」)。

