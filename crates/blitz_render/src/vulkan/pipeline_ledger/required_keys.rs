//! 起動時に完全構築する必要キー集合の数え上げ。担当するのは、「このレンダラーが描きうるパイプラインの全体」を
//! 1箇所で決め切ることである。
//!
//! 記録中に足りないキーを作らない(lazy生成をしない)ためには、要るキーを前もって数え上げられなければならない。
//! シーンの枝は材質変種キーの全変種ぶんであり、変種が増えれば数え上げも自動で増える。シャドウの枝は材質を読まないため1本である。

use super::key::パイプラインキー;
use super::lighting_binding_layout::照明束縛レイアウト;
use super::render_target::描画先の一意化;
use crate::vulkan::material_variant::材質変種キー;
use crate::vulkan::pipeline::色パスの深度状態;

pub(super) fn シーンのキー一覧(
    描画先: 描画先の一意化,
    照明束縛: 照明束縛レイアウト,
    深度状態: 色パスの深度状態,
) -> Vec<パイプラインキー> {
    材質変種キー::全変種
        .iter()
        .map(|材質変種| パイプラインキー::シーン {
            描画先,
            材質変種: *材質変種,
            照明束縛,
            深度状態,
        })
        .collect()
}

/// 深度プリパスのキー一覧。深度プリパスを積まない方式でも数え上げるのは、積むかどうかがフレームの組み立て方の選択であり、
/// パイプラインの有無をそこへ連動させると、方式を変えるたびに台帳の作り直しが要るためである。作るのは変種の数ぶんの1本だけである。
pub(super) fn 深度プリパスのキー一覧(描画先: 描画先の一意化) -> Vec<パイプラインキー> {
    材質変種キー::全変種
        .iter()
        .map(|材質変種| パイプラインキー::深度プリパス {
            描画先, 材質変種: *材質変種
        })
        .collect()
}

pub(super) fn シャドウのキー一覧(描画先: 描画先の一意化) -> Vec<パイプラインキー> {
    vec![パイプラインキー::シャドウ { 描画先 }]
}
