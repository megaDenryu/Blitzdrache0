//! レンダラーが1フレームのライティングに必要とする安全な入力契約。

use blitz_math::{ワールド, 光源クリップ, 変換, 座標変換エラー};

use crate::cascade::多段設定;

mod cascade_assembly;
mod components;
mod directional_light;
mod local_lights;
mod point_light;
mod point_light_visibility;
mod shadow;
mod shadow_casting;

pub use components::{ライティング入力エラー, 光強度, 光色, 環境光係数};
pub use local_lights::局所光源列;
pub use {directional_light::方向光入力, point_light::点光源入力, point_light_visibility::点光源の可視性};
pub use {shadow::影入力, shadow::影正射影範囲, shadow_casting::影の落ち方};

/// 1フレームのライティングの入力一式。`多段設定`は`生成する`が既定値を入れ、変えるときだけ差し替える。
#[derive(Debug, Clone, Copy)]
pub struct ライティング入力 {
    方向光: 方向光入力,
    局所光源列: 局所光源列,
    環境光: 環境光係数,
    影: 影入力,
    影の落ち方: 影の落ち方,
    多段設定: 多段設定, // 多段の分割と正射影の形を決める設定
    有効: bool,
}

impl ライティング入力 {
    pub fn 生成する(
        方向光: 方向光入力, 局所光源列: 局所光源列, 環境光: 環境光係数, 影: 影入力, 影の落ち方: 影の落ち方, 有効: bool
    ) -> Self {
        Self {
            方向光,
            局所光源列,
            環境光,
            影,
            影の落ち方,
            多段設定: 多段設定::既定(),
            有効,
        }
    }

    pub(crate) fn 方向光(&self) -> 方向光入力 {
        self.方向光
    }

    /// そのフレームの局所光の全件。件数0の世界も同じ型で表し、光を持たないことを別の状態にしない。
    pub fn 局所光源列(&self) -> 局所光源列 {
        self.局所光源列
    }

    pub(crate) fn 環境光(&self) -> 環境光係数 {
        self.環境光
    }

    pub fn 影注視点(&self) -> blitz_math::大域ワールド位置 {
        self.影.注視点()
    }

    /// 影の再構築パラメータだけを差し替えた値を返す。光の向き・色・強度を変えずに、影の正射影が覆う範囲だけを
    /// シーンごとに決めるためである。範囲が覆わない対象はシャドウマップに写らず、シャドウパスの可視判定でも落ちる。
    pub fn 影を差し替える(self, 影: 影入力) -> Self {
        Self { 影, ..self }
    }

    /// 方向光・環境光・影の落ち方だけを差し替えた値を返す。局所光源列・影の正射影範囲・ライティングの有効はそのまま残す。
    /// 時刻から導いた光を、世界が決めた影の範囲と局所光の上へ載せるために使う。
    pub fn 光を差し替える(self, 方向光: 方向光入力, 環境光: 環境光係数, 影の落ち方: 影の落ち方) -> Self {
        Self {
            方向光,
            環境光,
            影の落ち方,
            ..self
        }
    }

    pub(crate) fn 影を落とすか(&self) -> bool {
        self.影の落ち方.落とすか()
    }

    /// この`ライティング入力`が持つ1つの影の正射影から、与えた原点の相対フレームでライトビュー射影を組み立てる。
    /// 距離区分ごとの行列は`多段一式::距離区分のライトビュー射影`が同じ組立を通して作るため、判定と描画は同じ値を読む(2つの用途が別々に行列を組み立てると、判定に使った視錐台と実際に描く範囲がずれて影が欠ける)。
    /// 公開しているのは、世界の影方針から組んだ入力が有効な行列を作れることをエンジン側の検査が確かめるためである。
    /// 注意: 呼び出し元は対象の座標と同じカメラ大域原点を渡す責務を負う。
    pub fn ライトビュー射影を組み立てる(
        &self,
        相対フレーム原点: blitz_math::大域ワールド位置,
    ) -> Result<変換<ワールド, 光源クリップ>, 座標変換エラー> {
        self.影.ライトビュー射影を組み立てる(self.方向光, 相対フレーム原点)
    }

    pub(crate) fn 有効か(&self) -> bool {
        self.有効
    }
}
