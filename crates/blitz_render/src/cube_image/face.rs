//! 立方体画像の6つの面という概念そのものと、面と層番号との対応を所有する。
//! 触れる状態を持たず、担うのは面の同一性と並び順だけである。向きとの写像は`face_mapping`が持つ。
//!
//! 並びはVulkanの立方体画像の層番号の順に固定する。固定するのは、生成側が2次元配列の層へ書いた内容を
//! 消費側が立方体ビューの標本で参照するためであり、並びが食い違うと面ごとに絵が入れ替わる。
//!
//! 軸に世界の東西や天頂の名前を付けないのは、この面の並びが座標系を1つも仮定しないためである。
//! どの軸がどの世界の向きに当たるかは`sun_relative_frame`が決める。

/// 立方体の1面。0から順に第一軸の正・負、第二軸の正・負、第三軸の正・負である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 立方体の面 {
    第一軸の正,
    第一軸の負,
    第二軸の正,
    第二軸の負,
    第三軸の正,
    第三軸の負,
}

/// 層番号の小さい順に並べた全6面。焼く側が層を走査するのに使う。
pub const 立方体の全面: [立方体の面; 6] = [
    立方体の面::第一軸の正,
    立方体の面::第一軸の負,
    立方体の面::第二軸の正,
    立方体の面::第二軸の負,
    立方体の面::第三軸の正,
    立方体の面::第三軸の負,
];

impl 立方体の面 {
    pub fn 層番号(self) -> u32 {
        match self {
            Self::第一軸の正 => 0,
            Self::第一軸の負 => 1,
            Self::第二軸の正 => 2,
            Self::第二軸の負 => 3,
            Self::第三軸の正 => 4,
            Self::第三軸の負 => 5,
        }
    }

    /// 層番号から面を引く。0から5までの外はどの面でもないため値なしで返す。
    /// 型付きのエラーにしないのは、呼び出し元が「どの面でもない」ことを枝として扱うためであり、
    /// この関数はどの機能の語彙にも属さないためである。
    pub fn 層番号から求める(層番号: u32) -> Option<Self> {
        立方体の全面.into_iter().find(|面| 面.層番号() == 層番号)
    }
}
