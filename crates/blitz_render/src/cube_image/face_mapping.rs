//! 立方体の面の中の位置と向きとの行き来を担う工程。受け取るのは面と面内位置(または向き)、
//! 返すのは対応する向き(または面と面内位置)である。
//!
//! 軸の割り当てと符号はVulkanの立方体画像の面選択の規約に合わせる。合わせるのは、生成側が層番号へ書いた内容を
//! 消費側が立方体ビューの標本で参照するためであり、規約が食い違うと面の中で上下左右が反転する。
//!
//! 注意: この写像は`shaders/cube_face_mapping.slang`の写しを持つ。ここが正本であり、往復が恒等であることを
//! `face_mapping_tests`が検査する。

use super::face::立方体の面;

/// 面と面内位置から向きを求める。面内位置は横縦とも0以上1以下であり、0が面の左端・上端に当たる。
/// 返す向きは長さ1に正規化してある。面内位置が値域の中にある限り主軸の成分の絶対値が1であるため、単位化は必ず成功する。
pub fn 面と面内位置から向きを求める(面: 立方体の面, 横位置: f64, 縦位置: f64) -> [f64; 3] {
    let 横 = 2.0 * 横位置 - 1.0;
    let 縦 = 2.0 * 縦位置 - 1.0;
    let 生の向き = match 面 {
        立方体の面::第一軸の正 => [1.0, -縦, -横],
        立方体の面::第一軸の負 => [-1.0, -縦, 横],
        立方体の面::第二軸の正 => [横, 1.0, 縦],
        立方体の面::第二軸の負 => [横, -1.0, -縦],
        立方体の面::第三軸の正 => [横, -縦, 1.0],
        立方体の面::第三軸の負 => [-横, -縦, -1.0],
    };
    単位化する(生の向き)
}

/// 向きから面と面内位置を求める。`面と面内位置から向きを求める`の逆写像である。
/// 3成分すべてが0の向きは面を選べないため、その場合を`None`で表す。
pub fn 向きから面と面内位置を求める(向き: [f64; 3]) -> Option<(立方体の面, f64, f64)> {
    let [第一, 第二, 第三] = 向き;
    let 絶対値 = [第一.abs(), 第二.abs(), 第三.abs()];
    let 最大 = 絶対値[0].max(絶対値[1]).max(絶対値[2]);
    if !最大.is_finite() || 最大 <= 0.0 {
        return None;
    }
    let (面, 横, 縦) = 主軸で選ぶ(向き, 絶対値);
    Some((面, (横 / 最大 + 1.0) * 0.5, (縦 / 最大 + 1.0) * 0.5))
}

/// 絶対値が最大の成分で面を選び、残る2成分を面の横縦の向きへ割り当てる。
/// 等しい絶対値が並ぶ稜線では添字の小さい軸を選ぶ。どちらの面を選んでも同じ稜線上の同じ点を指すためである。
fn 主軸で選ぶ(向き: [f64; 3], 絶対値: [f64; 3]) -> (立方体の面, f64, f64) {
    let [第一, 第二, 第三] = 向き;
    if 絶対値[0] >= 絶対値[1] && 絶対値[0] >= 絶対値[2] {
        if 第一 > 0.0 {
            return (立方体の面::第一軸の正, -第三, -第二);
        }
        return (立方体の面::第一軸の負, 第三, -第二);
    }
    if 絶対値[1] >= 絶対値[2] {
        if 第二 > 0.0 {
            return (立方体の面::第二軸の正, 第一, 第三);
        }
        return (立方体の面::第二軸の負, 第一, -第三);
    }
    if 第三 > 0.0 {
        return (立方体の面::第三軸の正, 第一, -第二);
    }
    (立方体の面::第三軸の負, -第一, -第二)
}

/// テクセルの添字を、そのテクセルの中心が指す面内位置へ写す。焼く側が使う。
/// 一辺が2以上であることは解像度の生成が保証するため、この除算は0除算にならない。
pub fn テクセル中心の面内位置(添字: u32, 一辺: u32) -> f64 {
    (f64::from(添字) + 0.5) / f64::from(一辺)
}

/// 長さ1へそろえる。面内位置が値域の中にある限り主軸の成分の絶対値が1であるため、長さが0になることはない。
/// 大気の単位化を借りずに持つのは、この階層が大気を1つも知らないためである。
fn 単位化する(向き: [f64; 3]) -> [f64; 3] {
    let 長さ = (向き[0] * 向き[0] + 向き[1] * 向き[1] + 向き[2] * 向き[2]).sqrt();
    if !長さ.is_finite() || 長さ <= 0.0 {
        panic!("立方体の面内位置から長さ0の向きが出た(実装のバグ)");
    }
    [向き[0] / 長さ, 向き[1] / 長さ, 向き[2] / 長さ]
}
