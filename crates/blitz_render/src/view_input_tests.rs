//! 描画視点一覧が単一視点と複数視点を同じ非空型で保持することを検査する。

use blitz_math::{クリップ, ビュー, メートル, ラジアン, ワールド, 位置, 変換, 大域ワールド位置};

use crate::{描画視点, 描画視点一覧};

fn 視点を作る(x: f32) -> 描画視点 {
    let 位置 = 位置::<ワールド>::生成する(メートル::生成する(x), メートル::生成する(0.0), メートル::生成する(3.0));
    let 注視点 = 位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0));
    let ビュー: 変換<ワールド, ビュー> = 変換::注視(位置, 注視点);
    let 投影: 変換<ビュー, クリップ> = 変換::透視投影(ラジアン::度から(60.0), 1.0, メートル::生成する(0.1), メートル::生成する(100.0));
    let 大域位置 = 大域ワールド位置::局所ワールド位置から生成する(位置);
    描画視点::生成する(ビュー.合成する(投影), 大域位置, 大域位置)
}

#[test]
fn 先頭と残りから複数視点を保持する() {
    let 一覧 = 描画視点一覧::生成する(視点を作る(-0.03), vec![視点を作る(0.03)]);
    assert_eq!(一覧.視点数(), 2);
}
