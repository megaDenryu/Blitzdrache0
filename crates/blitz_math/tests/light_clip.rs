//! 光源クリップ空間の単体テスト: 既知のビュー空間点が正射影で期待座標に写ることの確認。
//! 参照: `_doc/開発スレッド/開発スレッド_2026-07-20_M0実装.md`「判断36」。

use blitz_math::{ビュー, メートル, 光源クリップ, 位置, 変換};

const 許容誤差: f32 = 1e-4;

fn ほぼ等しいか(左辺: f32, 右辺: f32) -> bool {
    (左辺 - 右辺).abs() < 許容誤差
}

#[test]
fn 既知の点が期待どおりの光源クリップ座標に写る() {
    let 横半幅 = 4.0_f32;
    let 縦半幅 = 4.0_f32;
    let 近 = 0.1_f32;
    let 遠 = 20.0_f32;

    let 正射影変換: 変換<ビュー, 光源クリップ> = 変換::正射影(
        メートル::生成する(横半幅),
        メートル::生成する(縦半幅),
        メートル::生成する(近),
        メートル::生成する(遠),
    );

    // ビュー空間で(2, 0, -5)の点(視点前方5m、横に2mずれた点)を写す。
    let ビュー空間点 = 位置::<ビュー>::生成する(
        メートル::生成する(2.0),
        メートル::生成する(0.0),
        メートル::生成する(-5.0),
    );
    let 光源クリップ座標 = 正射影変換.適用する(ビュー空間点);

    assert!(
        ほぼ等しいか(光源クリップ座標.x().値(), 0.5),
        "実測{}に対し期待0.5",
        光源クリップ座標.x().値()
    );
    assert!(
        ほぼ等しいか(光源クリップ座標.y().値(), 0.0),
        "実測{}に対し期待0.0",
        光源クリップ座標.y().値()
    );

    // 正射影(w=1)のNDC z = (z_view + near) / (near - far)。
    let 期待z = (-5.0 + 近) / (近 - 遠);
    assert!(
        ほぼ等しいか(光源クリップ座標.z().値(), 期待z),
        "実測{}に対し期待{期待z}",
        光源クリップ座標.z().値()
    );
}
