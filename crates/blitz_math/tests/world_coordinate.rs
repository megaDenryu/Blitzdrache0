//! 大きな大域座標どうしをf64で差し引いてからf32カメラ相対位置へ変換する境界を検査する。

use blitz_math::{大域メートル, 大域ワールド位置, 座標変換エラー};

#[test]
fn 千万メートル地点でも四分の一メートル差を保持する() {
    let カメラ = 大域ワールド位置::生成する(
        大域メートル::生成する(10_000_000.0),
        大域メートル::生成する(0.0),
        大域メートル::生成する(0.0),
    );
    let 対象 = 大域ワールド位置::生成する(
        大域メートル::生成する(10_000_000.25),
        大域メートル::生成する(0.0),
        大域メートル::生成する(0.0),
    );
    let Ok(相対) = 対象.カメラ相対へ変換する(カメラ) else {
        panic!("有限で小さい差分は変換できるはず");
    };
    assert_eq!(相対.x().値(), 0.25);
    assert_eq!(相対.y().値(), 0.0);
    assert_eq!(相対.z().値(), 0.0);
}

#[test]
fn f32範囲を超える差分は型付きエラーになる() {
    let 原点 = 大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(0.0), 大域メートル::生成する(0.0));
    let 遠方 = 大域ワールド位置::生成する(大域メートル::生成する(f64::MAX), 大域メートル::生成する(0.0), 大域メートル::生成する(0.0));
    assert_eq!(遠方.カメラ相対へ変換する(原点), Err(座標変換エラー::F32範囲外));
}
