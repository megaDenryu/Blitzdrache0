//! 変換の単体テスト: 合成の型整合、注視+逆Z透視投影で既知の点が期待座標に写ることの確認。

use blitz_math::{クリップ, ビュー, メートル, ラジアン, ワールド, 位置, 変換};

const 許容誤差: f32 = 1e-4;

fn ほぼ等しいか(左辺: f32, 右辺: f32) -> bool {
    (左辺 - 右辺).abs() < 許容誤差
}

/// 右手系・深度0..1規約でのNDC z値を、glamに頼らず独立に計算する。
/// 標準の透視投影を1から引き、近クリップで1、遠クリップで0になる。
fn 期待ndc_zを計算する(近: f32, 遠: f32, 視点からの距離: f32) -> f32 {
    let a = 遠 / (近 - 遠);
    let b = 近 * 遠 / (近 - 遠);
    let z_eye = -視点からの距離;
    let clip_z = a * z_eye + b;
    let clip_w = -z_eye;
    1.0 - clip_z / clip_w
}

#[test]
fn 合成の型整合と光軸上の既知点が期待クリップ座標に写る() {
    let 距離 = 3.0_f32;
    let 視点位置 = 位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(距離));
    let 注視点 = 位置::<ワールド>::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0));

    let ビュー変換: 変換<ワールド, ビュー> = 変換::注視(視点位置, 注視点);
    let 近 = 0.1_f32;
    let 遠 = 100.0_f32;
    let 投影変換: 変換<ビュー, クリップ> =
        変換::逆向き深度の透視投影(ラジアン::度から(60.0), 1.0, メートル::生成する(近), メートル::生成する(遠));

    // 合成: 型が合うときだけコンパイルできることそのものが検証。
    let ビュー射影変換: 変換<ワールド, クリップ> = ビュー変換.合成する(投影変換);

    let クリップ座標 = ビュー射影変換.適用する(注視点);
    assert!(ほぼ等しいか(クリップ座標.x().値(), 0.0));
    assert!(ほぼ等しいか(クリップ座標.y().値(), 0.0));

    let 期待z = 期待ndc_zを計算する(近, 遠, 距離);
    assert!(
        ほぼ等しいか(クリップ座標.z().値(), 期待z),
        "実測{}に対し期待{期待z}",
        クリップ座標.z().値()
    );
}

#[test]
fn 逆向き深度の投影は近面を1へ遠面を0へ写して単調に減る() {
    let 近 = 0.1_f32;
    let 遠 = 2000.0_f32;
    let 投影: 変換<ビュー, クリップ> =
        変換::逆向き深度の透視投影(ラジアン::度から(60.0), 16.0 / 9.0, メートル::生成する(近), メートル::生成する(遠));
    let 深度 = |距離: f32| {
        投影
            .適用する(位置::<ビュー>::生成する(
                メートル::生成する(0.0),
                メートル::生成する(0.0),
                メートル::生成する(-距離),
            ))
            .z()
            .値()
    };
    assert!(ほぼ等しいか(深度(近), 1.0));
    assert!(ほぼ等しいか(深度(遠), 0.0));
    assert!(深度(1.0) > 深度(10.0));
}

#[test]
fn 逆向き深度の投影と逆変換は位置を往復する() {
    let 投影: 変換<ビュー, クリップ> =
        変換::逆向き深度の透視投影(ラジアン::度から(60.0), 1.5, メートル::生成する(0.1), メートル::生成する(2000.0));
    let 点 = 位置::<ビュー>::生成する(メートル::生成する(1.0), メートル::生成する(-2.0), メートル::生成する(-50.0));
    let 戻した = 投影.逆変換する().適用する(投影.適用する(点));
    assert!(ほぼ等しいか(戻した.x().値(), 点.x().値()));
    assert!(ほぼ等しいか(戻した.y().値(), 点.y().値()));
    assert!(ほぼ等しいか(戻した.z().値(), 点.z().値()));
}
