//! 長さの型の表現の刻み幅の検査。隣の表現できる値との差そのものであることと、零のときに最小の非正規化数になることを固定する。
//! 型の定義から分けているのは、定義の側が演算子の実装だけを持つためである。

#![cfg(test)]

use super::meter::メートル;

#[test]
fn 表現の刻み幅は隣の表現できる値との差である() {
    assert_eq!(メートル::生成する(1.0).表現の刻み幅(), メートル::生成する(f32::EPSILON));
    assert_eq!(メートル::生成する(-1.0).表現の刻み幅(), メートル::生成する(f32::EPSILON));
    assert_eq!(メートル::生成する(0.5).表現の刻み幅(), メートル::生成する(f32::EPSILON / 2.0));
    assert_eq!(メートル::生成する(1.0e6).表現の刻み幅(), メートル::生成する(0.0625));
}

#[test]
fn 零の表現の刻み幅は最小の非正規化数である() {
    assert!(メートル::生成する(0.0).表現の刻み幅().値() > 0.0);
    assert!(メートル::生成する(0.0).表現の刻み幅().値() < f32::MIN_POSITIVE);
}
