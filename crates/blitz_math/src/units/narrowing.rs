//! 単位を持たない倍精度の量を単精度へ狭める境界。標準ライブラリはf64からf32への型付き変換を持たないため、
//! glamのベクタ縮小を1成分に使う。単位を持つ量の縮小(`大域秒`の秒への縮小等)はそれぞれの型が持ち、
//! ここが受けるのは割合のように次元を持たない量だけである。

use glam::DVec3;

use super::単位変換エラー;

/// 有限でない入力と、表現範囲を超えて無限大になった結果を型付きエラーにする。
pub fn 倍精度の無次元量を単精度へ狭める(値: f64) -> Result<f32, 単位変換エラー> {
    if !値.is_finite() {
        return Err(単位変換エラー::非有限値);
    }
    let 狭めた = DVec3::splat(値).as_vec3().x;
    if !狭めた.is_finite() {
        return Err(単位変換エラー::F32範囲外);
    }
    Ok(狭めた)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 単精度で表せる割合はそのまま狭まる() {
        assert_eq!(倍精度の無次元量を単精度へ狭める(0.5), Ok(0.5));
    }

    #[test]
    fn 非有限の入力を拒む() {
        assert_eq!(倍精度の無次元量を単精度へ狭める(f64::NAN), Err(単位変換エラー::非有限値));
    }

    #[test]
    fn 単精度の範囲を超える入力を拒む() {
        assert_eq!(倍精度の無次元量を単精度へ狭める(1.0e300), Err(単位変換エラー::F32範囲外));
    }
}
