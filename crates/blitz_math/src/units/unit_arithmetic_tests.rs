//! 単位型の算術の検査。担当するのは、同じ次元どうしの加減算とスカラー倍、次元の合成が別の次元の型になること、
//! 度からラジアンへの変換の3つを固定することである。
//!
//! 単位ごとの定義ファイルから分けているのは、この検査が複数の単位型にまたがるためである。

use super::{メートル, メートル毎秒, ラジアン, 秒};

const 許容誤差: f32 = 1e-5;

fn ほぼ等しいか(左辺: f32, 右辺: f32) -> bool {
    (左辺 - 右辺).abs() < 許容誤差
}

#[test]
fn メートルの加減算とスカラー倍() {
    let a = メートル::生成する(2.0);
    let b = メートル::生成する(3.0);
    assert!(ほぼ等しいか((a + b).値(), 5.0));
    assert!(ほぼ等しいか((b - a).値(), 1.0));
    assert!(ほぼ等しいか((a * 2.0).値(), 4.0));
}

#[test]
fn 秒の加減算() {
    let a = 秒::生成する(1.5);
    let b = 秒::生成する(0.5);
    assert!(ほぼ等しいか((a + b).値(), 2.0));
    assert!(ほぼ等しいか((a - b).値(), 1.0));
}

#[test]
fn ラジアンの度からの変換() {
    let 直角 = ラジアン::度から(90.0);
    assert!(ほぼ等しいか(直角.値(), std::f32::consts::FRAC_PI_2));

    let 半周 = ラジアン::度から(180.0);
    assert!(ほぼ等しいか(半周.値(), std::f32::consts::PI));
}

#[test]
fn 速度と時間の次元合成が距離になる() {
    let 速度 = メートル毎秒::生成する(4.0);
    let 時間 = 秒::生成する(2.5);
    let 距離: メートル = 速度 * 時間;
    assert!(ほぼ等しいか(距離.値(), 10.0));
}
