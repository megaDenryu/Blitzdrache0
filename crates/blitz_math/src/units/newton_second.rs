//! 衝撃の単位型。力と時間の積(運動量と同じ次元)を持ち、衝撃のベクトル(`衝撃`)の成分と大きさがこの型である。
//! 速度を逆質量で割った量と、位置の拘束のラグランジュ乗数を刻み幅で割った量も同じ次元であり、接触の速度段階が
//! 「接線の相対速度を零にする衝撃」と「法線反力が刻みの間に与えうる摩擦の衝撃の上限」をこの2つの合成で作る
//! (参照: `_doc/設計/剛体の状態と接触.md`「判断14」)。

use std::ops::Div;

use super::inverse_kilogram::逆キログラム;
use super::kilogram_meter::キログラムメートル;
use super::meter_per_second::メートル毎秒;
use super::second::秒;

/// ニュートン秒単位の衝撃の大きさ。生値の取り出しは境界(GPU・外部API)専用と明示する。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd, Default)]
#[repr(transparent)]
pub struct ニュートン秒(f32);

impl ニュートン秒 {
    pub const fn 生成する(値: f32) -> Self {
        Self(値)
    }

    /// 境界向けの生値取り出し。ドメインAPI内部では使わない。
    pub fn 値(&self) -> f32 {
        self.0
    }
}

/// 次元の合成: 速度 ÷ 逆質量 = 衝撃。その速度ぶんだけ相対速度を変えるのに要る衝撃である。
/// 前提: 逆質量は正である(有効逆質量が0の接触点は速度段階の前に除かれる)。
impl Div<逆キログラム> for メートル毎秒 {
    type Output = ニュートン秒;
    fn div(self, 逆質量: 逆キログラム) -> ニュートン秒 {
        ニュートン秒::生成する(self.値() / 逆質量.値())
    }
}

/// 次元の合成: 位置の拘束のラグランジュ乗数 ÷ 時間 = 衝撃。乗数を刻み幅で割ると、その刻みの間に働いた反力の衝撃になる。
impl Div<秒> for キログラムメートル {
    type Output = ニュートン秒;
    fn div(self, 経過時間: 秒) -> ニュートン秒 {
        ニュートン秒::生成する(self.値() / 経過時間.値())
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn 速度を逆質量で割ると衝撃になる() {
        let 衝撃 = メートル毎秒::生成する(3.0) / 逆キログラム::生成する(0.5).unwrap();
        assert_eq!(衝撃, ニュートン秒::生成する(6.0));
    }

    #[test]
    fn 乗数を刻み幅で割ると衝撃になる() {
        let 衝撃 = キログラムメートル::生成する(2.0) / 秒::生成する(0.25);
        assert_eq!(衝撃, ニュートン秒::生成する(8.0));
    }
}
