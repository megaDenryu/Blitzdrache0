//! 種と添字と用途から0以上1未満の小数を決める固定の混合関数。担当するのは値の決定だけであり、何に使うかを知らない。
//!
//! 生成器の可変状態を持たないため、走査順を変えても同じ添字と同じ用途からは常に同じ値が出る。
//! **これが生成の決定性の根拠である。**
//!
//! この層へ置くのは、散布(`blitz_asset_compiler`)と部品の展開(`blitz_assembly`)の両方が同じ混合を使い、
//! どちらか一方が写しを持つと、同じ種から違う配置が出る形の食い違いが生まれるためである。
//! 種の意味(その世界の乱数の種から導いた値か、生成の種か)は使う層が持ち、この層は生の値だけを受け取る。

mod use_number;

#[cfg(test)]
mod deterministic_value_tests;

pub use use_number::用途番号;

/// 種を保持し、添字と用途から0以上1未満の値を答える生成器。
///
/// 種を保持するのは、添字と用途と種がどれも整数であり、引数として並べると取り違えても型が通るためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct 決定的な値の生成器 {
    種: u64,
}

impl 決定的な値の生成器 {
    /// 種の生の値から作る。種を表す型は層ごとに違うため、この口は生の値を受ける。
    pub fn 種の値から生成する(種: u64) -> Self {
        Self { 種 }
    }

    pub fn 零以上一未満(&self, 添字: u64, 用途: 用途番号) -> f32 {
        let 上位 = 混ぜる(self.種 ^ 混ぜる(添字.wrapping_mul(0x9E37_79B9_7F4A_7C15) ^ 用途.値())) >> 48;
        let 十六ビット = match u16::try_from(上位) {
            Ok(値) => 値,
            Err(_) => panic!("48ビット右シフトの結果がu16に収まらないという不変条件に違反した"),
        };
        f32::from(十六ビット) / 65_536.0
    }
}

/// splitmix64の混合段。入力の1ビットの違いを出力全体へ広げるため、乗算と右シフトの排他的論理和を3回重ねる。
fn 混ぜる(値: u64) -> u64 {
    let mut z = 値.wrapping_add(0x9E37_79B9_7F4A_7C15);
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}
