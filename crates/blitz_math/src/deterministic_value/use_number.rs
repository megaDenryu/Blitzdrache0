//! 用途番号: 同じ添字から複数の独立した値を得るための、用途の区別。
//!
//! 裸の整数で渡さないのは、種も添字も用途もどれも整数であり、引数の順を取り違えても型が通るためである。
//! 取り違えても値は出るため、症状は「配置がなんとなく違う」という追いにくい形になる。
//!
//! 注意: 番号を決めるのは使う層である。**同じ種を使う2つの層が同じ番号を使うと、同じ値が出る。**
//! 層をまたいで同じ種を使うなら、番号の割り当ても層をまたいで一意にする。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct 用途番号(u64);

impl 用途番号 {
    pub fn 番号から生成する(番号: u64) -> Self {
        Self(番号)
    }

    pub(super) fn 値(self) -> u64 {
        self.0
    }
}
