//! 混合関数の試験。担当するのは、同じ入力から同じ値が出ることと、種・添字・用途のどれを変えても値が変わることを固定することである。
//!
//! これが生成の決定性の根拠であるため、値域と再現性をここで留める。混合の中身を変えると焼いた配置が全部変わる。

use super::use_number::用途番号;
use super::決定的な値の生成器;

fn 生成器(種: u64) -> 決定的な値の生成器 {
    決定的な値の生成器::種の値から生成する(種)
}

fn 用途(番号: u64) -> 用途番号 {
    用途番号::番号から生成する(番号)
}

#[test]
fn 同じ入力からは常に同じ値が出る() {
    let 一回目 = 生成器(42).零以上一未満(7, 用途(3));
    let 二回目 = 生成器(42).零以上一未満(7, 用途(3));
    assert_eq!(一回目, 二回目);
}

#[test]
fn 値は0以上1未満に収まる() {
    for 添字 in 0..2000_u64 {
        let 値 = 生成器(0x4F57_3420_5665_6765).零以上一未満(添字, 用途(1));
        assert!((0.0..1.0).contains(&値), "添字{添字}で値域を外れた: {値}");
    }
}

#[test]
fn 種を変えると値が変わる() {
    assert_ne!(生成器(1).零以上一未満(0, 用途(1)), 生成器(2).零以上一未満(0, 用途(1)));
}

#[test]
fn 添字を変えると値が変わる() {
    assert_ne!(生成器(1).零以上一未満(0, 用途(1)), 生成器(1).零以上一未満(1, 用途(1)));
}

/// 用途を分ける意味がここにある。同じ添字から複数の独立した値を得るために番号を変える。
#[test]
fn 用途を変えると値が変わる() {
    assert_ne!(生成器(1).零以上一未満(0, 用途(1)), 生成器(1).零以上一未満(0, 用途(2)));
}
