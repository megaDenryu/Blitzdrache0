//! 空間マーカー: 実行時表現を持たない幻影型で座標系を区別する。
//! `位置<空間>` `変換<入力空間, 出力空間>` の型パラメータとしてのみ使う。

/// 座標系マーカーを束ねるトレイト。実装は本ファイルの4空間のみを想定する。
pub trait 空間 {}

/// 原点・軸がシーン全体で共有される座標系。
pub enum ワールド {}
impl 空間 for ワールド {}

/// 個々のオブジェクトの原点を基準とする座標系。
pub enum ローカル {}
impl 空間 for ローカル {}

/// カメラを原点とし、カメラの向きを基準とする座標系。
pub enum ビュー {}
impl 空間 for ビュー {}

/// 透視投影後の座標系。
pub enum クリップ {}
impl 空間 for クリップ {}

/// 方向光のシャドウマップ生成に使う、光源から見た正射影後の座標系。
/// カメラの`クリップ`との混同を型で防ぐために別空間として区別する(判断36)。
pub enum 光源クリップ {}
impl 空間 for 光源クリップ {}
