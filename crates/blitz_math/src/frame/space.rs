//! 空間マーカー: 実行時表現を持たない幻影型で座標系を区別する。
//! `位置<空間>` `変換<入力空間, 出力空間>` の型パラメータとしてのみ使う。

/// 座標系マーカーを束ねるトレイト。実装は本ファイルの4空間のみを想定する。
pub trait 空間 {}

/// 原点・軸がシーン全体で共有される座標系。
pub enum ワールド {}
impl 空間 for ワールド {}

/// 個々のオブジェクトの原点を基準とする座標系。
pub enum ローカル {}
impl 空間 for ローカル {}

/// 部品1つの原点を基準とする座標系。接合点の位置と向きがここに住む。
/// `ローカル`(群のローカル空間。個体配置が住む)と別にするのは、接合点の位置をそのまま
/// 個体配置の平行移動へ渡す誤りを型で落とすためである。
/// 参照: `_doc/設計/部品カタログと接合点.md`「位置は部品ローカル空間の型で持つ」
pub enum 部品ローカル {}
impl 空間 for 部品ローカル {}

/// カメラを原点とし、カメラの向きを基準とする座標系。
pub enum ビュー {}
impl 空間 for ビュー {}

/// 剛体の主慣性の軸が張る座標系。主軸の回転(この座標系から重心局所座標へ)で慣性を対角の形に戻す。
/// 重心局所座標(`ローカル`)と別にするのは、主軸の回転を掛け忘れた慣性を重心局所の量として渡す誤りを型で落とすためである。
/// 参照: `_doc/設計/剛体の状態と接触.md`「判断4」
pub enum 主軸 {}
impl 空間 for 主軸 {}

/// 透視投影後の座標系。
pub enum クリップ {}
impl 空間 for クリップ {}

/// 方向光のシャドウマップ生成に使う、光源から見た正射影後の座標系。
/// カメラの`クリップ`との混同を型で防ぐために別空間として区別する(判断36)。
pub enum 光源クリップ {}
impl 空間 for 光源クリップ {}

/// 点光源の影の1つの面から見た、90度の透視投影後の座標系。
/// 方向光の`光源クリップ`と別にするのは、投影の種類も深度の作り方も違うためである。
/// 同じ空間にすると、方向光の正射影の行列を点光源の面の押し込み定数へ渡せてしまう。
pub enum 点光源の面クリップ {}
impl 空間 for 点光源の面クリップ {}
