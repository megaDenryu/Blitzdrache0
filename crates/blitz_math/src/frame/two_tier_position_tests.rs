//! 二段の位置の生成と繰り上げの試験。担当するのは、非有限の拒否と、繰り上げの前後で和が保存されること(反証(ii))と、
//! 生成が正規化済みの形で受けることを固定することである。蓄積・平行移動・速度の再構成の反証は
//! `two_tier_position_accumulation_tests.rs` が持つ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断3」の2026-09-08の実装の細目

#![allow(clippy::unwrap_used)]

use super::displacement::変位;
use super::position::位置;
use super::space::ワールド;
use super::two_tier_position::二段の位置;
use super::two_tier_position_error::二段の位置エラー;
use crate::units::{メートル, 倍精度の無次元量を単精度へ狭める};

pub(super) fn 位置を作る(x: f32, y: f32, z: f32) -> 位置<ワールド> {
    位置::生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

pub(super) fn 変位を作る(x: f32, y: f32, z: f32) -> 変位<ワールド> {
    変位::成分から生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
}

/// 粗い位置と細かい位置の和を倍精度で評価した値。2つの単精度の和は倍精度で厳密に表せるため、不変条件(1)の検査はこれで行う。
pub(super) fn 倍精度の和(対象: &二段の位置<ワールド>) -> [f64; 3] {
    let 和 = 対象.倍精度で評価した位置();
    [和.x().値(), 和.y().値(), 和.z().値()]
}

#[test]
fn 非有限の粗い位置と細かい位置を型付きエラーで拒む() {
    assert_eq!(
        二段の位置::粗い位置と細かい位置から生成する(位置を作る(f32::NAN, 0.0, 0.0), 変位::零()).err(),
        Some(二段の位置エラー::粗い位置が非有限)
    );
    assert_eq!(
        二段の位置::粗い位置と細かい位置から生成する(位置を作る(1.0, 0.0, 0.0), 変位を作る(0.0, f32::INFINITY, 0.0)).err(),
        Some(二段の位置エラー::細かい位置が非有限)
    );
}

#[test]
fn 位置から生成した二段の位置は畳むと元の位置に戻る() {
    let 元 = 位置を作る(18.335756, -9.168, 20.5);
    assert_eq!(二段の位置::位置から生成する(元).境界用に畳んだ位置(), 元);
}

/// 反証(ii): 細かい位置が表現の刻み幅の半分を超えると粗い位置が1刻み動き、和は倍精度で1ビットも変わらない。
#[test]
fn 繰り上げの前後で和が保存され粗い位置は一刻みだけ動く() {
    let 粗い = 位置を作る(20.5, 20.5, 20.5);
    let 刻み = メートル::生成する(20.5).表現の刻み幅().値();
    let 手前 = 二段の位置::粗い位置と細かい位置から生成する(粗い, 変位を作る(刻み * 0.4, 0.0, 0.0)).unwrap();
    let 越えた = 手前.変位を足す(変位を作る(刻み * 0.3, 0.0, 0.0));
    let 期待の和 = f64::from(20.5f32) + f64::from(刻み * 0.4) + f64::from(刻み * 0.3);
    assert!((倍精度の和(&越えた)[0] - 期待の和).abs() < 1.0e-12);
    assert_eq!(越えた.境界用に畳んだ位置().x().値(), 20.5 + 刻み);
    assert!(((越えた - 手前).x().値() - 刻み * 0.3).abs() < 刻み * 1.0e-3);
}

/// 生成は正規化済みの形で受ける。細かい位置に刻みの3倍を渡しても、粗い位置が3刻み動き細かい位置は残りだけになる。
#[test]
fn 生成は繰り上げてから受けるため細かい位置は刻みの半分以下に収まる() {
    let 刻み = メートル::生成する(20.5).表現の刻み幅().値();
    let 生成した = 二段の位置::粗い位置と細かい位置から生成する(位置を作る(20.5, 20.5, 20.5), 変位を作る(刻み * 3.0, 0.0, 0.0)).unwrap();
    assert_eq!(生成した.境界用に畳んだ位置().x().値(), 20.5 + 刻み * 3.0);
    let 細かい = 生成した - 生成した.境界用に畳んだ位置();
    assert!(細かい.x().値().abs() <= 刻み * 0.5);
    assert!((倍精度の和(&生成した)[0] - (f64::from(20.5f32) + f64::from(刻み * 3.0))).abs() < 1.0e-12);
}

// 決定的な擬似乱数(線形合同法)。変位の成分を −1 から 1 の範囲へ散らすためだけに使い、統計の性質は要らない。
fn 次の擬似乱数(状態: &mut u32) -> f32 {
    *状態 = 状態.wrapping_mul(1_664_525).wrapping_add(1_013_904_223);
    倍精度の無次元量を単精度へ狭める((f64::from(*状態 >> 8) / f64::from(1u32 << 24)).mul_add(2.0, -1.0)).unwrap()
}

/// 不変条件(4): 細かい位置を刻みの半分の直前(0.499刻み)に置き、腕0.5メートル級の変位を1回足した戻り値の細かい位置の
/// 各成分が、新しい粗い位置のその成分の表現の刻み幅の半分以下であること。2段の誤差なし加算の残りの和が半分を超えないことを固定する。
#[test]
fn 変位を足した後の細かい位置は粗い位置の刻みの半分以下に収まる() {
    let 刻み = メートル::生成する(20.5).表現の刻み幅().値();
    let 手前 = 二段の位置::粗い位置と細かい位置から生成する(
        位置を作る(20.5, -20.5, 20.5),
        変位を作る(刻み * 0.499, -刻み * 0.499, 刻み * 0.499),
    )
    .unwrap();
    let mut 状態 = 2026_0908_u32;
    for _ in 0..100 {
        let 変位 = 変位を作る(
            次の擬似乱数(&mut 状態) * 0.5,
            次の擬似乱数(&mut 状態) * 0.5,
            次の擬似乱数(&mut 状態) * 0.5,
        );
        let 足した = 手前.変位を足す(変位);
        let 粗い = 足した.境界用に畳んだ位置();
        let 細かい = 足した - 粗い;
        for (細かい成分, 粗い成分) in [(細かい.x(), 粗い.x()), (細かい.y(), 粗い.y()), (細かい.z(), 粗い.z())] {
            assert!(細かい成分.値().abs() <= 粗い成分.表現の刻み幅().値() * 0.5, "{足した:?} 変位={変位:?}");
        }
    }
}

#[test]
fn 単精度の位置との差は二段の細かい位置まで数える() {
    let 刻み = メートル::生成する(20.5).表現の刻み幅().値();
    let 二段 = 二段の位置::位置から生成する(位置を作る(20.5, 0.0, 0.0)).変位を足す(変位を作る(刻み * 0.25, 0.0, 0.0));
    assert!(((二段 - 位置を作る(20.5, 0.0, 0.0)).x().値() - 刻み * 0.25).abs() < 刻み * 1.0e-3);
    assert!(((位置を作る(20.5, 0.0, 0.0) - 二段).x().値() + 刻み * 0.25).abs() < 刻み * 1.0e-3);
}
