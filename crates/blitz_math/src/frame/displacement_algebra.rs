//! 変位のベクトル代数。担当するのは、成分からの生成・長さ・単位方向・外積・方向に沿う長さ・方向の成分の除去・長さの付け替えと、
//! ワールドの変位の水平成分である。変位の定義(`displacement.rs`)と分けるのは、あちらが位置との往復と定数倍だけを持つ型の定義であり、
//! こちらが掃引と滑りの反復(残りの変位から接触の単位法線の成分を除いて面に沿わせる)と段差の持ち上げ(水平移動の上限)が要る演算だからである。

use glam::Vec3;

use super::area_vector::面積ベクトル;
use super::direction::方向;
use super::direction_error::方向エラー;
use super::displacement::変位;
use super::space::{ワールド, 空間};
use crate::units::メートル;

impl<空間種: 空間> 変位<空間種> {
    /// 3つの成分から変位を作る。位置を経ずに変位だけを組みたい場面の入口である。
    pub fn 成分から生成する(x: メートル, y: メートル, z: メートル) -> Self {
        Self::内部から生成する(Vec3::new(x.値(), y.値(), z.値()))
    }

    pub fn 長さ(&self) -> メートル {
        メートル::生成する(self.内部ベクトル().length())
    }

    /// この変位の向き。零の変位は正規化で非有限になるため型付きエラーで拒む。
    pub fn 単位方向(&self) -> Result<方向<空間種>, 方向エラー> {
        let 正規化 = self.内部ベクトル() / self.内部ベクトル().length();
        方向::生成する(正規化.x, 正規化.y, 正規化.z)
    }

    /// 相手との外積。長さは2つの変位が張る平行四辺形の面積、向きはその面の法線(右手系)である。
    pub fn 外積(&self, 相手: &Self) -> 面積ベクトル<空間種> {
        面積ベクトル::内部から生成する(self.内部ベクトル().cross(相手.内部ベクトル()))
    }

    /// この変位を方向へ射影した長さ。方向の向きへ進む成分が正、逆へ進む成分が負である。
    pub fn 方向に沿う長さ(&self, 方向: 方向<空間種>) -> メートル {
        メートル::生成する(self.内部ベクトル().dot(方向.内部ベクトル()))
    }

    /// 方向に沿う成分を除いた変位。方向へ垂直な面に沿わせる操作であり、残る変位はその面に平行である。
    pub fn 方向の成分を除く(self, 方向: 方向<空間種>) -> Self {
        let 沿う長さ = self.内部ベクトル().dot(方向.内部ベクトル());
        Self::内部から生成する(self.内部ベクトル() - 方向.内部ベクトル() * 沿う長さ)
    }

    /// 向きを保ったまま長さを付け替えた変位。零の変位は向きを持たないため零のまま返す。
    pub fn 長さを付け替える(self, 長さ: メートル) -> Self {
        let 今の長さ = self.内部ベクトル().length();
        if 今の長さ <= 0.0 {
            return Self::零();
        }
        Self::内部から生成する(self.内部ベクトル() * (長さ.値() / 今の長さ))
    }

    pub fn 零か(&self) -> bool {
        self.内部ベクトル() == Vec3::ZERO
    }
}

impl 変位<ワールド> {
    /// 鉛直(第二軸)の成分を零にした変位。ワールドの鉛直は第二軸であるため、この空間にだけ水平がある。
    pub fn 水平成分(self) -> Self {
        Self::内部から生成する(Vec3::new(self.x().値(), 0.0, self.z().値()))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::frame::space::ワールド;
    use crate::frame::符号付きの座標軸;

    fn 変位を作る(x: f32, y: f32, z: f32) -> 変位<ワールド> {
        変位::成分から生成する(メートル::生成する(x), メートル::生成する(y), メートル::生成する(z))
    }

    #[test]
    fn 上向きの成分を除くと水平になる() {
        let 上 = 方向::<ワールド>::符号付きの座標軸から生成する(符号付きの座標軸::第二軸の正);
        let 沿わせた = 変位を作る(3.0, 4.0, 0.0).方向の成分を除く(上);
        assert_eq!(沿わせた, 変位を作る(3.0, 0.0, 0.0));
        assert_eq!(変位を作る(3.0, 4.0, 0.0).方向に沿う長さ(上), メートル::生成する(4.0));
        assert_eq!(変位を作る(3.0, 4.0, 5.0).水平成分(), 変位を作る(3.0, 0.0, 5.0));
    }

    #[test]
    fn 外積は面積と法線を持ち単位方向は長さ1になる() {
        let 外積 = 変位を作る(2.0, 0.0, 0.0).外積(&変位を作る(0.0, 3.0, 0.0));
        assert_eq!(外積.長さ(), crate::units::平方メートル::生成する(6.0));
        assert_eq!(外積.単位方向(), 方向::生成する(0.0, 0.0, 1.0));
        assert_eq!(変位を作る(0.0, 4.0, 0.0).単位方向(), 方向::生成する(0.0, 1.0, 0.0));
        assert!(変位::<ワールド>::零().単位方向().is_err());
    }

    #[test]
    fn 長さを付け替えても向きは変わらない() {
        assert_eq!(変位を作る(3.0, 4.0, 0.0).長さ(), メートル::生成する(5.0));
        assert_eq!(
            変位を作る(3.0, 4.0, 0.0).長さを付け替える(メートル::生成する(10.0)),
            変位を作る(6.0, 8.0, 0.0)
        );
        assert!(変位::<ワールド>::零().長さを付け替える(メートル::生成する(1.0)).零か());
    }
}
