//! 3軸を重ねる回転の試験。担当するのは、求めた回転が3軸を実際に重ねることと、左手系の組を拒むことを固定することである。
//!
//! 材料に実データの接合を使う。基礎の上面(法線が上、縦軸が奥)と2階の下面(法線が下、縦軸が奥)が向かい合うとき、
//! 求まる回転は恒等でなければならない。Blender側が採った組み立ての正解表もこの接合で回転を持たない。

#![allow(clippy::unwrap_used)]

use super::direction::方向;
use super::rotation::{クォータニオン, クォータニオンエラー};
use super::space::部品ローカル;

fn 方向を作る(x: f32, y: f32, z: f32) -> 方向<部品ローカル> {
    方向::生成する(x, y, z).unwrap()
}

/// 上面(法線+Y・縦軸+Z・横軸-X)と向かい合う枠(法線-Y・縦軸+Z・横軸+X)へ、
/// 下面の枠(法線-Y・縦軸+Z・横軸+X)を重ねる回転は恒等である。
#[test]
fn 向かい合う積層の接合で回転は恒等になる() {
    let 子の軸 = [方向を作る(1.0, 0.0, 0.0), 方向を作る(0.0, 0.0, 1.0), 方向を作る(0.0, -1.0, 0.0)];
    let 親の向かい合う軸 = [方向を作る(1.0, 0.0, 0.0), 方向を作る(0.0, 0.0, 1.0), 方向を作る(0.0, -1.0, 0.0)];
    let 回転 = クォータニオン::三つの軸を重ねる回転を求める(子の軸, 親の向かい合う軸).unwrap();
    assert_eq!(回転.成分(), [0.0, 0.0, 0.0, 1.0]);
}

/// 求めた回転が3軸を実際に重ねること。天頂まわりに90度回った枠へ重ねる。
#[test]
fn 求めた回転は3軸をそれぞれ重ねる() {
    let 入力 = [方向を作る(1.0, 0.0, 0.0), 方向を作る(0.0, 1.0, 0.0), 方向を作る(0.0, 0.0, 1.0)];
    let 出力 = [方向を作る(0.0, 0.0, -1.0), 方向を作る(0.0, 1.0, 0.0), 方向を作る(1.0, 0.0, 0.0)];
    let 回転 = クォータニオン::三つの軸を重ねる回転を求める(入力, 出力).unwrap();
    for (元, 先) in 入力.into_iter().zip(出力) {
        let 回した = 回転.方向を回す(元);
        assert!((回した.x() - 先.x()).abs() < 1.0e-5, "x成分が重ならない: {回した:?} と {先:?}");
        assert!((回した.y() - 先.y()).abs() < 1.0e-5, "y成分が重ならない: {回した:?} と {先:?}");
        assert!((回した.z() - 先.z()).abs() < 1.0e-5, "z成分が重ならない: {回した:?} と {先:?}");
    }
}

/// 左手系(鏡像)は回転では重ねられない。黙って通すと、得られた四元数が3軸のどれも正しく写さない。
#[test]
fn 左手系の軸の組を拒む() {
    let 右手系 = [方向を作る(1.0, 0.0, 0.0), 方向を作る(0.0, 1.0, 0.0), 方向を作る(0.0, 0.0, 1.0)];
    let 左手系 = [方向を作る(1.0, 0.0, 0.0), 方向を作る(0.0, 1.0, 0.0), 方向を作る(0.0, 0.0, -1.0)];
    assert!(matches!(
        クォータニオン::三つの軸を重ねる回転を求める(左手系, 右手系),
        Err(クォータニオンエラー::軸の組が右手系でない { .. })
    ));
}

/// 続けて回すの掛け順。90度を2回続けると180度になる。
#[test]
fn 続けて回すと2つの回転が順に効く() {
    let 入力 = [方向を作る(1.0, 0.0, 0.0), 方向を作る(0.0, 1.0, 0.0), 方向を作る(0.0, 0.0, 1.0)];
    let 四分の一 = [方向を作る(0.0, 0.0, -1.0), 方向を作る(0.0, 1.0, 0.0), 方向を作る(1.0, 0.0, 0.0)];
    let 回転: クォータニオン<部品ローカル, 部品ローカル> = クォータニオン::三つの軸を重ねる回転を求める(入力, 四分の一).unwrap();
    let 二回 = 回転.続けて回す(&回転);
    let 写した = 二回.方向を回す(方向を作る(1.0, 0.0, 0.0));
    assert!((写した.x() + 1.0).abs() < 1.0e-5, "180度回れば逆を向く: {写した:?}");
}
