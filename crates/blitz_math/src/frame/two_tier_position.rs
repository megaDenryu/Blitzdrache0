//! 二段の位置: 空間に属する3次元の位置を、粗い位置(単精度の位置)と細かい位置(単精度の変位)の和として持つ型。
//! 単精度の位置1本では、原点から20メートル離れた座標の表現の刻み幅(2e-6メートルの桁)より小さい補正を足しても
//! 丸めで消えるか1刻みへ跳ぶ。剛体の重心の世界位置がその補正を失わないために、この型が和を2つの単精度で持つ。
//! 不変条件は次のとおりである。(1)数学的な位置は粗い位置と細かい位置の和であり、和を1本の単精度へ畳んだ値を状態として持たない。
//! (2)微小な補正はまず細かい位置へ足す(`変位を足す`)。(3)繰り上げで粗い位置を動かしたときは、動いた量を細かい位置から
//! 差し引いて和を保存する。(4)細かい位置の各成分の絶対値は粗い位置のその成分の表現の刻み幅の半分以下に保つ。
//! 繰り上げは誤差なし加算(2つの単精度の和を「最も近い表現できる値」と「その丸めの残り」へ厳密に分ける算法)で行うため、
//! 粗い位置は和を最も近い値へ丸めたもの、細かい位置はその残りそのものになり、(3)と(4)が同時に成り立つ。
//! 和を単精度の位置として取り出す口は`境界用に畳んだ位置`の1つであり、GPU境界・描画の変換の生成・衝突数学層へ渡す
//! 形の中心の3つの境界だけが読む(`cargo xtask conform`が白リスト外の呼び出しを落とす)。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断3」、`_doc/計画/ユビキタス言語.md`「二段の位置」

use std::fmt;

use glam::Vec3;

use super::displacement::変位;
use super::position::位置;
use super::space::空間;
use super::two_tier_position_error::二段の位置エラー;

/// 型パラメータ`空間`が属する座標系の位置を、粗い位置と細かい位置の和として持つ。
pub struct 二段の位置<空間種> {
    粗い位置: 位置<空間種>,
    細かい位置: 変位<空間種>,
}

impl<空間種: 空間> 二段の位置<空間種> {
    /// 単精度の位置をそのまま粗い位置にし、細かい位置を零にした二段の位置。
    pub fn 位置から生成する(位置: 位置<空間種>) -> Self {
        Self {
            粗い位置: 位置,
            細かい位置: 変位::零(),
        }
    }

    /// 粗い位置と細かい位置の組から生成する。和を保ったまま繰り上げて正規化した形で受け、非有限の成分を型付きエラーで拒む。
    pub fn 粗い位置と細かい位置から生成する(
        粗い位置: 位置<空間種>,
        細かい位置: 変位<空間種>,
    ) -> Result<Self, 二段の位置エラー> {
        if !粗い位置.内部ベクトル().is_finite() {
            return Err(二段の位置エラー::粗い位置が非有限);
        }
        if !細かい位置.内部ベクトル().is_finite() {
            return Err(二段の位置エラー::細かい位置が非有限);
        }
        Ok(Self::繰り上げて生成する(粗い位置.内部ベクトル(), 細かい位置.内部ベクトル()))
    }

    // 粗い位置と細かい位置の和を、成分ごとの誤差なし加算で「最も近い表現できる値」と「その残り」へ分けて持つ。
    pub(super) fn 繰り上げて生成する(粗い: Vec3, 細かい: Vec3) -> Self {
        let 和 = 粗い + 細かい;
        let 残り = Vec3::new(
            誤差なし加算の残り(粗い.x, 細かい.x, 和.x),
            誤差なし加算の残り(粗い.y, 細かい.y, 和.y),
            誤差なし加算の残り(粗い.z, 細かい.z, 和.z),
        );
        Self {
            粗い位置: 位置::内部から生成する(和),
            細かい位置: 変位::内部から生成する(残り),
        }
    }

    // 変位を細かい位置へ足してから繰り上げる。細かい位置と変位の和を先に誤差なし加算で分け(腕0.5メートルのような大きい変位を
    // 1e-6メートル級の細かい位置へ単精度で足す丸めを残りとして拾う)、その和と粗い位置をもう1度誤差なし加算で分け、2つの残りを
    // 細かい位置にする。1段だけの誤差なし加算では前者の丸め(3e-8メートル級)が捨てられ、細分ごとの雑音になる。
    pub(super) fn 変位を足して繰り上げる(粗い: Vec3, 細かい: Vec3, 変位: Vec3) -> Self {
        let 細かいと変位の和 = 細かい + 変位;
        let 細かいと変位の残り = Vec3::new(
            誤差なし加算の残り(細かい.x, 変位.x, 細かいと変位の和.x),
            誤差なし加算の残り(細かい.y, 変位.y, 細かいと変位の和.y),
            誤差なし加算の残り(細かい.z, 変位.z, 細かいと変位の和.z),
        );
        let 繰り上げた = Self::繰り上げて生成する(粗い, 細かいと変位の和);
        Self {
            粗い位置: 繰り上げた.粗い位置,
            細かい位置: 変位::内部から生成する(繰り上げた.細かい内部ベクトル() + 細かいと変位の残り),
        }
    }

    pub(super) fn 粗い内部ベクトル(&self) -> Vec3 {
        self.粗い位置.内部ベクトル()
    }

    pub(super) fn 細かい内部ベクトル(&self) -> Vec3 {
        self.細かい位置.内部ベクトル()
    }

    /// 粗い位置と細かい位置の和を最も近い単精度へ丸めた位置。境界(GPU・描画の変換の生成・衝突数学層へ渡す形の中心)だけが読む。
    /// CPUの物理がこれを読むと、二段で持った意味が失われる(`cargo xtask conform`が白リスト外の呼び出しを落とす)。
    pub fn 境界用に畳んだ位置(&self) -> 位置<空間種> {
        位置::内部から生成する(self.粗い内部ベクトル() + self.細かい内部ベクトル())
    }
}

// 2つの単精度 a・b とその丸めた和 s について、a + b − s を厳密に求める(Knuthの誤差なし加算)。
// 3つの数に対して対等な計算であるためレシーバを持たない。積和融合が無いRustの単精度の加減算で厳密である。
fn 誤差なし加算の残り(a: f32, b: f32, 和: f32) -> f32 {
    let bの寄与 = 和 - a;
    (a - (和 - bの寄与)) + (b - bの寄与)
}

// 手動実装: deriveは幻影型パラメータ自身にも境界を要求するが、空間種は実行時表現を持たない。
impl<空間種> Clone for 二段の位置<空間種> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<空間種> Copy for 二段の位置<空間種> {}

impl<空間種> PartialEq for 二段の位置<空間種> {
    fn eq(&self, 相手: &Self) -> bool {
        self.粗い位置 == 相手.粗い位置 && self.細かい位置 == 相手.細かい位置
    }
}

impl<空間種> fmt::Debug for 二段の位置<空間種> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("二段の位置")
            .field("粗い位置", &self.粗い位置)
            .field("細かい位置", &self.細かい位置)
            .finish()
    }
}
