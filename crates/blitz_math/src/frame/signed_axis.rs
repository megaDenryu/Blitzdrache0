//! 座標軸とその符号という概念そのものと、それが指す単位方向。
//!
//! 軸に沿う向き(成分が±1と0だけからなる向き)は`方向::生成する`の長さの検査を必ず通るため、
//! 呼び出し元は到達しない`Result`を扱うことになる。到達しない失敗の経路を作らないよう、
//! 軸を型で受けて検査そのものを不要にする口をここが持つ。

use glam::Vec3;

use super::direction::方向;
use super::space::空間;

/// 座標軸のどれを、正と負のどちらの向きに取るかを表す6つの値。第一軸から第三軸という呼び方は
/// どの軸が世界のどの向きに当たるかを決めない。それを決めるのは、この軸を使う側の座標系である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 符号付きの座標軸 {
    第一軸の正,
    第一軸の負,
    第二軸の正,
    第二軸の負,
    第三軸の正,
    第三軸の負,
}

impl<空間種: 空間> 方向<空間種> {
    /// 符号付きの座標軸が指す単位方向を作る。成分は±1と0そのものであり、丸めも正規化も入らない。
    pub fn 符号付きの座標軸から生成する(軸: 符号付きの座標軸) -> Self {
        let 内部 = match 軸 {
            符号付きの座標軸::第一軸の正 => Vec3::X,
            符号付きの座標軸::第一軸の負 => Vec3::NEG_X,
            符号付きの座標軸::第二軸の正 => Vec3::Y,
            符号付きの座標軸::第二軸の負 => Vec3::NEG_Y,
            符号付きの座標軸::第三軸の正 => Vec3::Z,
            符号付きの座標軸::第三軸の負 => Vec3::NEG_Z,
        };
        Self::内部から生成する(内部)
    }
}
