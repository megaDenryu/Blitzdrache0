//! 大域ワールド位置と局所の変位の往復。位置へ変位を足すと位置になる、という位置の側の口である。
//! 大域ワールド位置の定義(`global_world_position.rs`)と分けるのは、あちらがf64からf32へ狭める境界を担当し、
//! こちらが逆向き(f32の変位をf64の位置へ足す)を担当するためである。位置と変位の往復(`position_displacement.rs`)と同じ形である。

use glam::DVec3;

use super::displacement::変位;
use super::global_world_position::大域ワールド位置;
use super::space::ワールド;

impl 大域ワールド位置 {
    /// 局所の変位のぶんだけ動かした大域位置。変位は単精度であり、足す先の倍精度へ広げるだけで丸めは入らない。
    pub fn 局所の変位を足す(self, 変位: 変位<ワールド>) -> Self {
        Self::倍精度の内部から生成する(self.倍精度の内部() + DVec3::from(変位.内部ベクトル()))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::units::{メートル, 大域メートル};

    #[test]
    fn 変位を足すと成分ごとに動く() {
        let 位置 = 大域ワールド位置::生成する(大域メートル::生成する(1.0), 大域メートル::生成する(2.0), 大域メートル::生成する(3.0));
        let 動いた = 位置.局所の変位を足す(変位::成分から生成する(
            メートル::生成する(0.5),
            メートル::生成する(-2.0),
            メートル::生成する(0.0),
        ));
        assert_eq!(動いた.x(), 大域メートル::生成する(1.5));
        assert_eq!(動いた.y(), 大域メートル::生成する(0.0));
        assert_eq!(動いた.z(), 大域メートル::生成する(3.0));
    }
}
