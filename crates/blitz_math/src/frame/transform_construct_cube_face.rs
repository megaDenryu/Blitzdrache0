//! 立方体の1つの面から見るための変換の生成関数。面の直交基底で姿勢を決めるビュー変換と、
//! 正方形の面を90度の視野で写す透視投影の2つを持つ。
//!
//! 面の向きを注視点でなく基底で受けるのは、立方体画像の面の規約が、この描画系のビュー空間の右手系に対して
//! 鏡像だからである。右・上・前方の3つ組は右×上が前方の逆向きにならない組であり、注視の生成が仮定する
//! 右手系では作れない。行列式が負になるため三角形の巻き方が反転する。
//! 注意: この変換で描くパスはカリングを行ってはならない。行うなら巻き方を反転させること
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断m」)。

use glam::{Mat4, Vec3, Vec4};

use super::position::位置;
use super::space::{ビュー, ワールド, 点光源の面クリップ};
use super::transform::変換;
use crate::units::{メートル, ラジアン};

/// 立方体の1つの面が持つ視野の全角。6面で全方位を隙間なく覆うため90度で固定である。
const 面の視野の全角: f32 = std::f32::consts::FRAC_PI_2;

impl 変換<ワールド, ビュー> {
    /// 立方体の1つの面の直交基底で姿勢を決めるビュー変換を作る。
    ///
    /// 前提: 3つの向きは長さ1で互いに直交していること。呼び出し元が軸の並べ替えと符号反転だけで作ることを前提にし、
    /// この関数は正規化も直交化も行わない(丸めを持ち込まないためである)。
    pub fn 立方体の面の基底から生成する(
        視点位置: 位置<ワールド>, 右向き: [f32; 3], 上向き: [f32; 3], 前方向き: [f32; 3]
    ) -> Self {
        let 回転 = Mat4::from_cols(
            Vec4::new(右向き[0], 上向き[0], -前方向き[0], 0.0),
            Vec4::new(右向き[1], 上向き[1], -前方向き[1], 0.0),
            Vec4::new(右向き[2], 上向き[2], -前方向き[2], 0.0),
            Vec4::new(0.0, 0.0, 0.0, 1.0),
        );
        let 視点へ寄せる = Mat4::from_translation(-視点位置.内部ベクトル());
        変換::内部から生成する(回転 * 視点へ寄せる)
    }
}

impl 変換<ビュー, 点光源の面クリップ> {
    /// 立方体の1つの面の透視投影。視野の全角は90度、縦横の比は1で固定であり、動くのは近面と遠面だけである。
    ///
    /// 注意: 深度は順Z(近面が0、遠面が1)である。同じ向きの比較深度をCPU正本とSlangの写しが別に作るため、
    /// この投影の第3行を変えたらその2つも変える(参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断m」)。
    pub fn 立方体の面の透視投影(近面: メートル, 遠面: メートル) -> Self {
        let 投影 = Mat4::perspective_rh(面の視野の全角, 1.0, 近面.値(), 遠面.値());
        let y反転 = Mat4::from_scale(Vec3::new(1.0, -1.0, 1.0));
        変換::内部から生成する(y反転 * 投影)
    }

    /// この投影が使う視野の全角。呼び出し元が面の錐台を組み立てるために読む。
    pub fn 面の視野の全角() -> ラジアン {
        ラジアン::生成する(面の視野の全角)
    }
}
