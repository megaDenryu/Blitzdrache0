//! 空間に属する衝撃。成分はニュートン秒(運動量と同じ次元)であり、腕との外積(回転衝撃)の次元の合成を持つ。
//! 衝撃 × 逆質量 = 速度は速度の側(`velocity.rs`)が持つ。力と別の型にするのは、ゲーム側が力を毎刻み加えるつもりで衝撃を加える誤りを型で止めるためである
//! (参照: `_doc/設計/剛体の状態と接触.md`「判断5」「判断6」)。

use super::angular_impulse::回転衝撃;
use super::displacement::変位;
use super::space::空間;
use super::vector_quantity::三成分の量を定義する;
use crate::units::ニュートン秒;

三成分の量を定義する! {
    /// ワールドまたは剛体の局所に属する衝撃(ニュートン秒の3成分)。瞬間に運動量を変える作用である。
    衝撃, ニュートン秒
}

impl<空間種: 空間> 変位<空間種> {
    /// 腕(この変位)に掛かる衝撃が生む回転衝撃 r × P。任意の点へ衝撃を加えたときに剛体の側が回転衝撃へ写す式である。
    pub fn 腕に掛かる衝撃の回転衝撃(&self, 衝撃: 衝撃<空間種>) -> 回転衝撃<空間種> {
        回転衝撃::内部から生成する(self.内部ベクトル().cross(衝撃.内部ベクトル()))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::frame::space::ワールド;
    use crate::units::{ニュートンメートル秒, メートル};

    #[test]
    fn 腕と衝撃の外積は回転衝撃になる() {
        let 腕 = 変位::<ワールド>::成分から生成する(メートル::生成する(0.0), メートル::生成する(1.0), メートル::生成する(0.0));
        let 衝撃 = 衝撃::成分から生成する(ニュートン秒::生成する(0.0), ニュートン秒::生成する(0.0), ニュートン秒::生成する(5.0));
        assert_eq!(腕.腕に掛かる衝撃の回転衝撃(衝撃).x(), ニュートンメートル秒::生成する(5.0));
    }
}
