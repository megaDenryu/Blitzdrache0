//! 回転の生成の検査。担当するのは、非有限の成分と長さがゼロに近い成分を型付きエラーで拒むことと、
//! 有限で長さが1でない成分を正規化して受け入れること(アセットの浮動小数点誤差の吸収)を固定することである。

use super::rotation::{クォータニオン, クォータニオンエラー};
use super::space::ローカル;

#[test]
fn 非有限の成分を拒みゼロ長を拒み有限の非単位長は正規化して受け入れる() {
    for 成分 in [
        [f32::NAN, 0.0, 0.0, 1.0],
        [0.0, f32::INFINITY, 0.0, 1.0],
        [0.0, 0.0, f32::NEG_INFINITY, 1.0],
        [0.0, 0.0, 0.0, f32::NAN],
    ] {
        let [x, y, z, w] = 成分;
        assert!(
            matches!(
                クォータニオン::<ローカル, ローカル>::生成する(x, y, z, w),
                Err(クォータニオンエラー::非有限成分 { .. })
            ),
            "{成分:?}"
        );
    }
    assert!(matches!(
        クォータニオン::<ローカル, ローカル>::生成する(0.0, 0.0, 0.0, 0.0),
        Err(クォータニオンエラー::ゼロ長)
    ));
    let Ok(回転) = クォータニオン::<ローカル, ローカル>::生成する(0.0, 0.0, 0.0, 2.0) else {
        panic!("有限で長さ2の成分は正規化して受理される");
    };
    assert_eq!(回転.境界用xyzw配列(), [0.0, 0.0, 0.0, 1.0]);
}
