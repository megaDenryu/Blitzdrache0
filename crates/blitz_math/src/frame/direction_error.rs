//! 方向の生成と演算の失敗。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! 注意: blitz_mathはglamのみに依存する方針(数学DDD最小セットの外部依存最小化)のため
//! thiserrorを使わず`std::error::Error`を手動実装する。様式は`rotation.rs`の`クォータニオンエラー`に倣う。

use std::fmt;

/// `単位長でない`が黙って正規化せず拒むのは、長さが1から離れた宣言が作者の書き誤りであり、
/// 正規化して受け入れると誤りが絵に出るまで誰にも見えなくなるためである。
/// `直交していない`が持つ`外積の長さ`は、2つの単位方向の外積の長さがなす角の正弦であることを使い、
/// 1から離れていれば直交していないと判定する値である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 方向エラー {
    非有限成分 { 成分: &'static str },
    単位長でない { 長さ: f32 },
    直交していない { 外積の長さ: f32 },
}

impl fmt::Display for 方向エラー {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::非有限成分 { 成分 } => write!(f, "方向の{成分}成分が有限でない"),
            Self::単位長でない { 長さ } => write!(f, "方向の長さが1でない(長さ{長さ})"),
            Self::直交していない { 外積の長さ } => {
                write!(f, "2つの方向が直交していない(外積の長さ{外積の長さ}。直交していれば1になる)")
            }
        }
    }
}

impl std::error::Error for 方向エラー {}
