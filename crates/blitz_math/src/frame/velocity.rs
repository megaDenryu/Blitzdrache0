//! 空間に属する並進の速度。成分はメートル毎秒であり、速度 × 秒 = 変位、変位 ÷ 秒 = 速度、衝撃 × 逆質量 = 速度の次元の合成を持つ。
//! 変位を「1刻みの変位」として速度の代わりに持たないのは、細分の刻み幅が変わると意味が変わる量を状態にしないためである
//! (参照: `_doc/設計/剛体の状態と接触.md`「判断5」)。

use std::ops::{Div, Mul};

use super::direction::方向;
use super::direction_error::方向エラー;
use super::displacement::変位;
use super::impulse::衝撃;
use super::space::空間;
use super::vector_quantity::三成分の量を定義する;
use crate::units::{メートル毎秒, 秒, 逆キログラム};

三成分の量を定義する! {
    /// ワールドまたは剛体の局所に属する並進の速度(メートル毎秒の3成分)。
    速度, メートル毎秒
}

impl<空間種: 空間> 速度<空間種> {
    /// この速度が向いている単位方向。長さが0の速度は方向を持たないため型付きエラーで返る。
    /// 接触の速度段階が接線の相対速度から動摩擦の向きを取り出すのに読む(判断14)。
    pub fn 単位方向(&self) -> Result<方向<空間種>, 方向エラー> {
        let 内部 = self.内部ベクトル();
        方向::生成する(内部.x, 内部.y, 内部.z)
    }

    /// 指定の方向の成分を取り除いた速度。接触の法線方向を除くと接線方向の相対速度になる。
    pub fn 方向の成分を除く(self, 方向: 方向<空間種>) -> Self {
        self - Self::方向へ生成する(方向, self.方向に沿う成分(方向))
    }
}

/// 次元の合成: 速度 × 時間 = 変位。
impl<空間種: 空間> Mul<秒> for 速度<空間種> {
    type Output = 変位<空間種>;
    fn mul(self, 経過時間: 秒) -> 変位<空間種> {
        変位::内部から生成する(self.内部ベクトル() * 経過時間.値())
    }
}

/// 次元の合成: 変位 ÷ 時間 = 速度。確定した位置と前の位置の差から速度を再構成する式がこの形である。
impl<空間種: 空間> Div<秒> for 変位<空間種> {
    type Output = 速度<空間種>;
    fn div(self, 経過時間: 秒) -> 速度<空間種> {
        速度::内部から生成する(self.内部ベクトル() / 経過時間.値())
    }
}

/// 次元の合成: 衝撃 × 逆質量 = 速度。
impl<空間種: 空間> Mul<逆キログラム> for 衝撃<空間種> {
    type Output = 速度<空間種>;
    fn mul(self, 逆質量: 逆キログラム) -> 速度<空間種> {
        速度::内部から生成する(self.内部ベクトル() * 逆質量.値())
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;
    use crate::frame::space::ワールド;
    use crate::units::{ニュートン秒, メートル};

    #[test]
    fn 速度に時間を掛けると変位になり変位を時間で割ると速度へ戻る() {
        let 速度 =
            速度::<ワールド>::成分から生成する(メートル毎秒::生成する(2.0), メートル毎秒::生成する(0.0), メートル毎秒::生成する(-4.0));
        let 変位 = 速度 * 秒::生成する(0.5);
        assert_eq!(
            変位,
            変位::成分から生成する(メートル::生成する(1.0), メートル::生成する(0.0), メートル::生成する(-2.0))
        );
        assert_eq!(変位 / 秒::生成する(0.5), 速度);
    }

    #[test]
    fn 衝撃に逆質量を掛けると速度になる() {
        let 衝撃 =
            衝撃::<ワールド>::成分から生成する(ニュートン秒::生成する(4.0), ニュートン秒::生成する(0.0), ニュートン秒::生成する(0.0));
        assert_eq!((衝撃 * 逆キログラム::生成する(0.5).unwrap()).x(), メートル毎秒::生成する(2.0));
    }
}
