//! 慣性テンソルと逆慣性テンソルの検査。担当するのは、主軸と主慣性からの生成が対角の形に戻ること・角運動量と一般化逆質量の値・
//! ジャイロ項の陰的1段が主軸上の角速度を変えず主軸の外の角速度の向きを変えることを固定することである。

#![allow(clippy::unwrap_used)]

use super::angular_velocity::角速度;
use super::direction::方向;
use super::displacement::変位;
use super::inertia_tensor::慣性テンソル;
use super::inverse_inertia_tensor::逆慣性テンソル;
use super::rotation::クォータニオン;
use super::space::ローカル;
use crate::units::{
    キログラムメートル, キログラム平方メートル, メートル, ラジアン毎秒, 秒, 逆キログラム平方メートル
};

fn 主慣性() -> [キログラム平方メートル; 3] {
    [
        キログラム平方メートル::生成する(1.0),
        キログラム平方メートル::生成する(2.0),
        キログラム平方メートル::生成する(3.0),
    ]
}

fn 角速度を作る(x: f32, y: f32, z: f32) -> 角速度<ローカル> {
    角速度::成分から生成する(ラジアン毎秒::生成する(x), ラジアン毎秒::生成する(y), ラジアン毎秒::生成する(z))
}

fn 恒等の主軸() -> クォータニオン<ローカル, ローカル> {
    クォータニオン::恒等()
}

#[test]
fn 主軸が恒等なら角運動量は主慣性を成分ごとに掛けた値になる() {
    let 慣性 = 慣性テンソル::<ローカル>::主軸と主慣性から生成する(&恒等の主軸(), 主慣性());
    let 角運動量 = 慣性.角速度を角運動量へ写す(角速度を作る(1.0, 1.0, 1.0));
    assert_eq!([角運動量.x().値(), 角運動量.y().値(), 角運動量.z().値()], [1.0, 2.0, 3.0]);
}

#[test]
fn 主軸上の角速度はジャイロ項の陰的1段で変わらず主軸の外では向きが変わる() {
    let 慣性 = 慣性テンソル::<ローカル>::主軸と主慣性から生成する(&恒等の主軸(), 主慣性());
    let 刻み幅 = 秒::生成する(1.0 / 480.0);
    let 主軸上 = 角速度を作る(0.0, 10.0, 0.0);
    assert!((慣性.ジャイロ項を陰的に一段解く(主軸上, 刻み幅) - 主軸上).長さ().値() < 1.0e-5);
    let 主軸の外 = 角速度を作る(3.0, 7.0, 5.0);
    let 解いた = 慣性.ジャイロ項を陰的に一段解く(主軸の外, 刻み幅);
    assert!((解いた - 主軸の外).長さ().値() > 1.0e-3, "解いた{解いた:?}");
}

#[test]
fn 逆慣性テンソルの一般化逆質量と乗数の回転は主軸が恒等なら成分ごとの式になる() {
    let 逆主慣性 = 主慣性().map(|j| j.逆慣性().unwrap());
    let 逆慣性 = 逆慣性テンソル::<ローカル>::主軸と逆主慣性から生成する(&恒等の主軸(), 逆主慣性);
    let 腕 = 変位::成分から生成する(メートル::生成する(2.0), メートル::生成する(0.0), メートル::生成する(0.0));
    let 上 = 方向::生成する(0.0, 1.0, 0.0).unwrap();
    // r × n = (0, 0, 2) であり、(r × n)ᵀ I⁻¹ (r × n) = 4 ÷ 3 になる。
    assert!((逆慣性.腕と向きの一般化逆質量の寄与(腕, 上).値() - 4.0 / 3.0).abs() < 1.0e-6);
    assert!((逆慣性.向きの一般化逆質量(上).値() - 0.5).abs() < 1.0e-6);
    let 回転 = 逆慣性.腕に作用する乗数の回転(腕, 上, キログラムメートル::生成する(1.5));
    assert!((回転.z().値() - 1.0).abs() < 1.0e-6, "回転{回転:?}");
    let 零 = 逆慣性テンソル::<ローカル>::零();
    assert!(零.腕と向きの一般化逆質量の寄与(腕, 上).零か());
    assert_eq!(零.向きの一般化逆質量(上), 逆キログラム平方メートル::零());
}

#[test]
fn 主軸を回すと慣性テンソルも回った軸で対角になる() {
    let 主軸 = クォータニオン::<super::space::主軸, ローカル>::生成する(
        0.0,
        0.0,
        std::f32::consts::FRAC_1_SQRT_2,
        std::f32::consts::FRAC_1_SQRT_2,
    )
    .unwrap();
    let 慣性 = 慣性テンソル::<ローカル>::主軸と主慣性から生成する(&主軸, 主慣性());
    // 第一主軸(主慣性1)が重心局所のy軸へ回るため、y軸まわりの角速度の角運動量は1倍になる。
    let 角運動量 = 慣性.角速度を角運動量へ写す(角速度を作る(0.0, 1.0, 0.0));
    assert!(
        (角運動量.y().値() - 1.0).abs() < 1.0e-5 && 角運動量.x().値().abs() < 1.0e-5,
        "{角運動量:?}"
    );
}
