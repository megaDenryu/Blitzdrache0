//! 空間に属する角速度。成分はラジアン毎秒であり、角速度 × 秒 = 回転ベクトルの次元の合成を持つ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断5」「判断8」。

use std::ops::Mul;

use super::rotation_vector::回転ベクトル;
use super::space::空間;
use super::vector_quantity::三成分の量を定義する;
use crate::units::{ラジアン毎秒, 秒};

三成分の量を定義する! {
    /// ワールドまたは剛体の局所に属する角速度(ラジアン毎秒の3成分)。向きが回転の軸、長さが回る速さである。
    角速度, ラジアン毎秒
}

/// 次元の合成: 角速度 × 時間 = 回転ベクトル(その時間に回る角)。
impl<空間種: 空間> Mul<秒> for 角速度<空間種> {
    type Output = 回転ベクトル<空間種>;
    fn mul(self, 経過時間: 秒) -> 回転ベクトル<空間種> {
        回転ベクトル::内部から生成する(self.内部ベクトル() * 経過時間.値())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::frame::space::ワールド;
    use crate::units::ラジアン;

    #[test]
    fn 角速度に時間を掛けると回転ベクトルになる() {
        let 角速度 = 角速度::<ワールド>::成分から生成する(
            ラジアン毎秒::生成する(0.0),
            ラジアン毎秒::生成する(3.0),
            ラジアン毎秒::生成する(0.0),
        );
        assert_eq!((角速度 * 秒::生成する(0.5)).y(), ラジアン::生成する(1.5));
    }
}
