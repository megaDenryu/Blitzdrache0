//! 空間に属する角速度。成分はラジアン毎秒であり、角速度 × 秒 = 回転ベクトルの次元の合成と、角運動量との外積(ジャイロ項の回転力)を持つ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断5」「判断8」。

use std::ops::Mul;

use super::angular_impulse::回転衝撃;
use super::rotation_vector::回転ベクトル;
use super::space::空間;
use super::torque::回転力;
use super::vector_quantity::三成分の量を定義する;
use crate::units::{ラジアン毎秒, 秒};

三成分の量を定義する! {
    /// ワールドまたは剛体の局所に属する角速度(ラジアン毎秒の3成分)。向きが回転の軸、長さが回る速さである。
    角速度, ラジアン毎秒
}

impl<空間種: 空間> 角速度<空間種> {
    /// 角運動量との外積 ω × L。単位はラジアン毎秒 × ニュートンメートル秒 = ニュートンメートルであり、
    /// ジャイロ項 −ω × (I ω) を回転力として書くときの材料である(陽的な更新の反証が使う)。
    pub fn 角運動量との外積(&self, 角運動量: 回転衝撃<空間種>) -> 回転力<空間種> {
        回転力::内部から生成する(self.内部ベクトル().cross(角運動量.内部ベクトル()))
    }
}

/// 次元の合成: 角速度 × 時間 = 回転ベクトル(その時間に回る角)。
impl<空間種: 空間> Mul<秒> for 角速度<空間種> {
    type Output = 回転ベクトル<空間種>;
    fn mul(self, 経過時間: 秒) -> 回転ベクトル<空間種> {
        回転ベクトル::内部から生成する(self.内部ベクトル() * 経過時間.値())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::frame::space::ワールド;
    use crate::units::{ニュートンメートル, ニュートンメートル秒, ラジアン};

    #[test]
    fn 角速度に時間を掛けると回転ベクトルになる() {
        let 角速度 = 角速度::<ワールド>::成分から生成する(
            ラジアン毎秒::生成する(0.0),
            ラジアン毎秒::生成する(3.0),
            ラジアン毎秒::生成する(0.0),
        );
        assert_eq!((角速度 * 秒::生成する(0.5)).y(), ラジアン::生成する(1.5));
    }

    #[test]
    fn 角運動量との外積は回転力になる() {
        let 角速度 = 角速度::<ワールド>::成分から生成する(
            ラジアン毎秒::生成する(1.0),
            ラジアン毎秒::生成する(0.0),
            ラジアン毎秒::生成する(0.0),
        );
        let 角運動量 = 回転衝撃::成分から生成する(
            ニュートンメートル秒::生成する(0.0),
            ニュートンメートル秒::生成する(2.0),
            ニュートンメートル秒::生成する(0.0),
        );
        assert_eq!(角速度.角運動量との外積(角運動量).z(), ニュートンメートル::生成する(2.0));
    }
}
