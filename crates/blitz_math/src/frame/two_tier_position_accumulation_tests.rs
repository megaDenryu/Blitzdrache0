//! 二段の位置の反証のうち、蓄積(反証(i))・平行移動の不変(反証(iii))・速度の再構成の跳びの不在(反証(iv))の3本。
//! いずれも単精度の位置1本へ同じ補正を足した反証を並べ、そちらが落ちる形にする。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断3」の2026-09-08の実装の細目

#![allow(clippy::unwrap_used)]

use super::two_tier_position::二段の位置;
use super::two_tier_position_tests::{位置を作る, 倍精度の和, 変位を作る};
use crate::units::メートル;

// 20メートル程度の座標の表現の刻み幅の10分の1。単精度の位置1本へ足すと丸めで消える大きさである。
fn 刻みの十分の一の補正() -> f32 {
    メートル::生成する(20.5).表現の刻み幅().値() * 0.1
}

/// 反証(i): 1刻みより小さい補正を100回足すと、途中で消えず最終の有効位置へ蓄積される。単精度の位置は1度も動かない。
#[test]
fn 刻みより小さい補正が百回の加算で蓄積される() {
    let 補正 = 刻みの十分の一の補正();
    let 元 = 位置を作る(20.5, 18.335756, 9.168);
    let mut 二段 = 二段の位置::位置から生成する(元);
    let mut 単精度 = 元;
    for _ in 0..100 {
        二段 = 二段.変位を足す(変位を作る(補正, 補正, 補正));
        単精度 = 単精度.変位を足す(変位を作る(補正, 補正, 補正));
    }
    let 期待 = f64::from(補正) * 100.0;
    let 和 = 倍精度の和(&二段);
    assert!((和[0] - f64::from(20.5f32) - 期待).abs() < 1.0e-9);
    assert!((和[1] - f64::from(18.335756f32) - 期待).abs() < 1.0e-9);
    assert!((和[2] - f64::from(9.168f32) - 期待).abs() < 1.0e-9);
    assert_eq!(単精度, 元);
}

/// 反証(iii): 同じ微小な変位の列を、原点付近と(1000, 2000, 3000)メートルへ平行移動した位置へ加えても、相対変位が一致する。
#[test]
fn 大きな平行移動をしても同じ微小な相対変位が得られる() {
    let 補正 = 刻みの十分の一の補正();
    let mut 近く = 二段の位置::位置から生成する(位置を作る(0.5, 0.25, 0.125));
    let mut 遠く = 二段の位置::位置から生成する(位置を作る(1000.5, 2000.25, 3000.125));
    let (近くの元, 遠くの元) = (近く, 遠く);
    for 回 in 0..50 {
        let 向き = if 回 % 3 == 0 { -1.0 } else { 1.0 };
        近く = 近く.変位を足す(変位を作る(補正 * 向き, 補正 * 2.0, -補正));
        遠く = 遠く.変位を足す(変位を作る(補正 * 向き, 補正 * 2.0, -補正));
    }
    let 差 = (遠く - 遠くの元) - (近く - 近くの元);
    assert!(差.長さ().値() < 1.0e-9);
    assert!((近く - 近くの元).長さ().値() > 補正 * 10.0);
}

/// 反証(iv): 刻みより小さい変位 c を毎細分足して速度を (x − x_前) ÷ h で再構成すると、どの細分でも c ÷ h と一致し、
/// 粗い位置の1刻み ÷ h の跳びが現れない。単精度の位置は毎細分1刻みへ丸められ、速度は c ÷ h でなく 1刻み ÷ h(1.67倍)になる。
#[test]
fn 補正前後から再構成した速度が粗い位置の刻み単位の跳びにならない() {
    let 刻み = メートル::生成する(20.5).表現の刻み幅().値();
    let 補正 = 刻み * 0.6;
    let 刻み幅の秒 = 1.0 / 960.0;
    let mut 二段 = 二段の位置::位置から生成する(位置を作る(20.5, 0.0, 0.0));
    let mut 単精度 = 位置を作る(20.5, 0.0, 0.0);
    let mut 単精度の速さ一覧 = Vec::new();
    for _ in 0..20 {
        let 次 = 二段.変位を足す(変位を作る(補正, 0.0, 0.0));
        let 速さ = (次 - 二段).x().値() / 刻み幅の秒;
        assert!((速さ - 補正 / 刻み幅の秒).abs() <= (補正 / 刻み幅の秒) * 1.0e-6);
        二段 = 次;
        let 単精度の次 = 単精度.変位を足す(変位を作る(補正, 0.0, 0.0));
        単精度の速さ一覧.push((単精度の次 - 単精度).x().値() / 刻み幅の秒);
        単精度 = 単精度の次;
    }
    let 一刻みの速さ = 刻み / 刻み幅の秒;
    assert!(単精度の速さ一覧.iter().all(|速さ| (*速さ - 一刻みの速さ).abs() < 1.0e-9 * 一刻みの速さ));
    assert!((倍精度の和(&二段)[0] - (f64::from(20.5f32) + f64::from(補正) * 20.0)).abs() < 1.0e-9);
}
