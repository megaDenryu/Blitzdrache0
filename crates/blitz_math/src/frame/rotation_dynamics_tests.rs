//! 回転の力学の操作の検査。担当するのは、微小回転の更新が長さ1を保つこと(正規化を外した反証で離れること)・2つの回転ベクトルへの写しが生成の逆になること・
//! 逆回転と逆慣性テンソルの回転が期待の形になることを固定することである。
//! 乱数の角速度は決定的な値の生成器で作り、実行ごとに同じ列を回す。

#![allow(clippy::unwrap_used)]

use super::angular_velocity::角速度;
use super::inverse_inertia_tensor::逆慣性テンソル;
use super::rotation::クォータニオン;
use super::rotation_vector::回転ベクトル;
use super::space::{ローカル, ワールド};
use crate::deterministic_value::{決定的な値の生成器, 用途番号};
use crate::units::{ラジアン, ラジアン毎秒, 秒, 逆キログラム平方メートル};

fn 回転ベクトルを作る(x: f32, y: f32, z: f32) -> 回転ベクトル<ワールド> {
    回転ベクトル::成分から生成する(ラジアン::生成する(x), ラジアン::生成する(y), ラジアン::生成する(z))
}

fn 乱数の角速度(生成器: &決定的な値の生成器, 番号: u64) -> 角速度<ワールド> {
    let 成分 = |用途: u64| ラジアン毎秒::生成する(生成器.零以上一未満(番号, 用途番号::番号から生成する(用途)) * 20.0 - 10.0);
    角速度::成分から生成する(成分(1), 成分(2), 成分(3))
}

// 判断3の検査: 乱数の角速度で1万細分積分した後の長さが1から1e-5以内である。反証: 正規化を外すと長さが1から離れる。
#[test]
fn 微小回転の更新を1万回重ねても長さは1のままであり正規化を外すと離れる() {
    let 生成器 = 決定的な値の生成器::種の値から生成する(7);
    let 刻み幅 = 秒::生成する(1.0 / 480.0);
    let mut 正規化する = クォータニオン::<ローカル, ワールド>::生成する(0.0, 0.0, 0.0, 1.0).unwrap();
    let mut 正規化しない = 正規化する;
    for 番号 in 0..10_000u64 {
        let 回転 = 乱数の角速度(&生成器, 番号) * 刻み幅;
        正規化する = 正規化する.微小回転で更新する(回転);
        正規化しない = 正規化しない.正規化せずに微小回転で更新する(回転);
    }
    assert!(正規化する.長さの1からのずれ() < 1.0e-5, "ずれ{}", 正規化する.長さの1からのずれ());
    assert!(
        正規化しない.長さの1からのずれ() > 1.0e-3,
        "反証: ずれ{}",
        正規化しない.長さの1からのずれ()
    );
}

#[test]
fn 対数写像は回転ベクトルからの生成の逆であり微小回転の写しは小さい角で一致する() {
    let 回転 = 回転ベクトルを作る(0.3, -0.5, 0.2);
    let 四元数 = クォータニオン::<ワールド, ワールド>::回転ベクトルから生成する(回転);
    let 戻した = 四元数.対数写像で回転ベクトルへ();
    assert!((戻した - 回転).長さ().値() < 1.0e-6, "戻した{戻した:?}");
    let 微小 = 回転ベクトルを作る(1.0e-3, 0.0, 0.0);
    let 一次 = クォータニオン::<ワールド, ワールド>::回転ベクトルから生成する(微小).微小回転として回転ベクトルへ();
    assert!((一次 - 微小).長さ().値() < 1.0e-8, "一次{一次:?}");
    assert_eq!(
        クォータニオン::<ワールド, ワールド>::恒等().対数写像で回転ベクトルへ(),
        回転ベクトル::零()
    );
}

// 実部が負の四元数(長い弧)も短い弧として読む。
#[test]
fn 実部が負でも短い弧の回転ベクトルを返す() {
    let 回転 = 回転ベクトルを作る(0.0, 1.0, 0.0);
    let q = クォータニオン::<ワールド, ワールド>::回転ベクトルから生成する(回転);
    let [x, y, z, w] = q.成分();
    let 反転 = クォータニオン::<ワールド, ワールド>::生成する(-x, -y, -z, -w).unwrap();
    assert!((反転.対数写像で回転ベクトルへ() - 回転).長さ().値() < 1.0e-6);
}

#[test]
fn 逆回転を続けて回すと恒等になり逆慣性テンソルは回転した軸で読める() {
    let 姿勢 = クォータニオン::<ローカル, ワールド>::回転ベクトルから生成する(
        回転ベクトルを作る(0.0, 0.0, std::f32::consts::FRAC_PI_2),
    );
    let 往復 = 姿勢.続けて回す(&姿勢.逆回転());
    assert!(往復.対数写像で回転ベクトルへ().長さ().値() < 1.0e-6);
    let 逆慣性 = 逆慣性テンソル::<ローカル>::主軸と逆主慣性から生成する(
        &クォータニオン::<ローカル, ローカル>::恒等(),
        [
            逆キログラム平方メートル::生成する(1.0).unwrap(),
            逆キログラム平方メートル::生成する(0.5).unwrap(),
            逆キログラム平方メートル::生成する(0.25).unwrap(),
        ],
    );
    let ワールド = 姿勢.逆慣性テンソルを回す(&逆慣性);
    let x = super::direction::方向::<ワールド>::生成する(1.0, 0.0, 0.0).unwrap();
    let y = super::direction::方向::<ワールド>::生成する(0.0, 1.0, 0.0).unwrap();
    assert!((ワールド.向きの一般化逆質量(x).値() - 0.5).abs() < 1.0e-6);
    assert!((ワールド.向きの一般化逆質量(y).値() - 1.0).abs() < 1.0e-6);
}
