//! 単位方向のベクトル代数。担当するのは、2つの方向の内積(なす角の余弦)と、3つの方向のスカラー三重積である。
//! 方向の定義(`direction.rs`)と分けるのは、あちらが生成と直交する方向の導出という不変条件の側を持ち、
//! こちらが曲げ拘束の角の評価(二面角の余弦と正弦、線分のなす角の余弦)が要る無次元の演算だからである。

use super::direction::方向;
use super::space::空間;

impl<空間種: 空間> 方向<空間種> {
    /// なす角の余弦。どちらも単位長であるため無次元である。
    pub fn 内積(&self, 相手: &Self) -> f32 {
        self.内部ベクトル().dot(相手.内部ベクトル())
    }

    /// スカラー三重積 self · (第二 × 第三)。第二と第三の張る面に対する自分の向きの符号を持ち、二面角の正弦がこれである。
    pub fn 三重積(&self, 第二: &Self, 第三: &Self) -> f32 {
        self.内部ベクトル().dot(第二.内部ベクトル().cross(第三.内部ベクトル()))
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;
    use crate::frame::space::ワールド;

    #[test]
    fn 内積は余弦で三重積は右手系の3軸で1になる() {
        let x = 方向::<ワールド>::生成する(1.0, 0.0, 0.0).unwrap();
        let y = 方向::<ワールド>::生成する(0.0, 1.0, 0.0).unwrap();
        let z = 方向::<ワールド>::生成する(0.0, 0.0, 1.0).unwrap();
        assert_eq!(x.内積(&x), 1.0);
        assert_eq!(x.内積(&y), 0.0);
        assert_eq!(x.三重積(&y, &z), 1.0);
        assert_eq!(x.三重積(&z, &y), -1.0);
    }
}
