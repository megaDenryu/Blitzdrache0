//! 空間に属する回転ベクトル。向きが回転の軸、長さが回る角(ラジアン)であり、微小な回転と角速度 × 秒の結果を表す。
//! 回転ベクトル ÷ 秒 = 角速度の次元の合成と、軸に沿う角(ねじりの拘束違反)を持つ。単位四元数からこの型へは`クォータニオン`の側が写す。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断8」「判断9」「判断10」。

use std::ops::Div;

use super::angular_velocity::角速度;
use super::space::空間;
use super::vector_quantity::三成分の量を定義する;
use crate::units::{ラジアン, 秒};

三成分の量を定義する! {
    /// ワールドまたは剛体の局所に属する回転ベクトル(ラジアンの3成分)。
    回転ベクトル, ラジアン
}

/// 次元の合成: 回転ベクトル ÷ 時間 = 角速度。確定した姿勢と前の姿勢の差から角速度を再構成する式がこの形である。
impl<空間種: 空間> Div<秒> for 回転ベクトル<空間種> {
    type Output = 角速度<空間種>;
    fn div(self, 経過時間: 秒) -> 角速度<空間種> {
        角速度::内部から生成する(self.内部ベクトル() / 経過時間.値())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::frame::space::ワールド;
    use crate::units::ラジアン毎秒;

    #[test]
    fn 回転ベクトルを時間で割ると角速度になる() {
        let 回転 =
            回転ベクトル::<ワールド>::成分から生成する(ラジアン::生成する(0.0), ラジアン::生成する(0.0), ラジアン::生成する(1.0));
        assert_eq!((回転 / 秒::生成する(0.25)).z(), ラジアン毎秒::生成する(4.0));
    }
}
