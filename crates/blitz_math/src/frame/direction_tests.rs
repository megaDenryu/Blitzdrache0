//! 方向の生成と演算の試験。担当するのは、無言の正規化をしないことと、直交していない2つを拒むことの2つを固定することである。
//! どちらも黙って通すと、宣言の誤りが絵に出るまで誰にも見えなくなる形の欠陥になる。
//!
//! 実データの値を使うのは、接合面の軸の対応の規約(横軸は上方向と向きの外積)が実物と合っていることを、
//! 文書の主張でなくコードで固定するためである。参照: `_doc/設計/部品カタログと接合点.md`「接合面の幅と高さがどの軸に対応するか」

#![allow(clippy::unwrap_used)]

use super::direction::方向;
use super::direction_error::方向エラー;
use super::space::部品ローカル;

fn 方向を作る(x: f32, y: f32, z: f32) -> 方向<部品ローカル> {
    方向::生成する(x, y, z).unwrap()
}

#[test]
fn 単位長の入力を受け入れる() {
    let 上向き = 方向を作る(0.0, 1.0, 0.0);
    assert_eq!(上向き.y(), 1.0);
}

#[test]
fn 長さが1から離れた入力を無言で正規化せず拒む() {
    assert!(matches!(
        方向::<部品ローカル>::生成する(0.0, 2.0, 0.0),
        Err(方向エラー::単位長でない { .. })
    ));
    assert!(matches!(
        方向::<部品ローカル>::生成する(0.0, 0.0, 0.0),
        Err(方向エラー::単位長でない { .. })
    ));
}

#[test]
fn 非有限の成分を拒む() {
    assert_eq!(
        方向::<部品ローカル>::生成する(f32::NAN, 1.0, 0.0),
        Err(方向エラー::非有限成分 { 成分: "x" })
    );
}

/// 実データの上面の接合点は 向きが(0, 1, 0)・上方向が(0, 0, 1) であり、幅6.0がX方向の寸法と一致する。
/// 規約どおり横軸を「上方向と向きの外積」で求めると、X軸に沿った方向が出る。
#[test]
fn 上面の接合点の横軸はx軸に沿う() {
    let 向き = 方向を作る(0.0, 1.0, 0.0);
    let 上方向 = 方向を作る(0.0, 0.0, 1.0);
    let 横軸 = 上方向.直交する方向を求める(&向き).unwrap();
    assert_eq!(横軸, 方向を作る(-1.0, 0.0, 0.0));
}

/// 実データの正面壁は 向きが(0, 0, 1)・上方向が(0, 1, 0) であり、幅6.0がX方向の寸法と一致する。
#[test]
fn 正面壁の接合点の横軸はx軸に沿う() {
    let 向き = 方向を作る(0.0, 0.0, 1.0);
    let 上方向 = 方向を作る(0.0, 1.0, 0.0);
    let 横軸 = 上方向.直交する方向を求める(&向き).unwrap();
    assert_eq!(横軸, 方向を作る(1.0, 0.0, 0.0));
}

/// 横軸と縦軸と法線が右手系をなすこと。横軸と縦軸の外積が法線へ戻る。
#[test]
fn 横軸と縦軸と法線は右手系をなす() {
    let 向き = 方向を作る(0.0, 1.0, 0.0);
    let 上方向 = 方向を作る(0.0, 0.0, 1.0);
    let 横軸 = 上方向.直交する方向を求める(&向き).unwrap();
    assert_eq!(横軸.直交する方向を求める(&上方向).unwrap(), 向き);
}

#[test]
fn 直交していない2つの方向を拒む() {
    let 向き = 方向を作る(0.0, 1.0, 0.0);
    assert!(matches!(向き.直交する方向を求める(&向き), Err(方向エラー::直交していない { .. })));
}

#[test]
fn 逆を向く方向は全成分の符号を反転する() {
    assert_eq!(方向を作る(0.0, 0.0, 1.0).逆を向く方向(), 方向を作る(0.0, 0.0, -1.0));
}
