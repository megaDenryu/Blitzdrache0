//! 正規直交な3軸どうしを重ねる回転の生成。受け取るのは入力空間の3軸と出力空間の3軸、返すのはその2組を重ねる回転である。
//!
//! 回転そのものの定義から分けているのは、これが「2つの枠の対応から回転を導く」という1つの工程であり、
//! 呼び出し元が中身(行列を組んで転置を掛けること)を知らずに呼べるためである。
//!
//! 接合の計算がこの口を使う。子の接合面の枠を、親の接合面と向かい合う枠へ重ねる回転が、そのまま部品の姿勢になる。

use glam::{Mat3, Quat};

use super::direction::方向;
use super::rotation::{クォータニオン, クォータニオンエラー};
use super::space::空間;

/// 行列式が1から離れてよい幅。3軸が単位長で互いに直交していれば行列式はちょうど1か-1になり、
/// 焼かれたf32の丸めがこの幅に収まる。`direction.rs`の単位長の許容差と同じ考え方で置く。
const 行列式の許容差: f32 = 1.0e-3;

impl<入力空間: 空間, 出力空間: 空間> クォータニオン<入力空間, 出力空間> {
    /// 入力空間の3軸を、出力空間の3軸へ順に重ねる回転を求める。
    ///
    /// 3軸は横・縦・法の順であり、この順で右手系をなしていなければならない。
    /// **左手系(鏡像)の組は回転では重ねられない。** そのまま行列を作ると鏡映が混ざり、
    /// 得られた四元数が3軸のどれも正しく写さないまま値としては成立してしまうため、型付きエラーで拒む。
    pub fn 三つの軸を重ねる回転を求める(
        入力の軸: [方向<入力空間>; 3],
        出力の軸: [方向<出力空間>; 3],
    ) -> Result<Self, クォータニオンエラー> {
        let 入力行列 = 軸から行列を組む(&入力の軸);
        let 出力行列 = 軸から行列を組む(&出力の軸);
        右手系かを確かめる(入力行列.determinant())?;
        右手系かを確かめる(出力行列.determinant())?;
        Ok(Self::内部から生成する(Quat::from_mat3(&(出力行列 * 入力行列.transpose()))))
    }
}

fn 軸から行列を組む<空間種: 空間>(軸: &[方向<空間種>; 3]) -> Mat3 {
    Mat3::from_cols(軸[0].内部ベクトル(), 軸[1].内部ベクトル(), 軸[2].内部ベクトル())
}

fn 右手系かを確かめる(行列式: f32) -> Result<(), クォータニオンエラー> {
    if (行列式 - 1.0).abs() <= 行列式の許容差 {
        return Ok(());
    }
    Err(クォータニオンエラー::軸の組が右手系でない { 行列式 })
}
