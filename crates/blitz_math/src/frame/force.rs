//! 空間に属する力。成分はニュートンであり、力 × 秒 = 衝撃と、腕との外積(回転力)の次元の合成を持つ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断5」「判断6」。

use std::ops::Mul;

use super::displacement::変位;
use super::impulse::衝撃;
use super::space::空間;
use super::torque::回転力;
use super::vector_quantity::三成分の量を定義する;
use crate::units::{ニュートン, 秒};

三成分の量を定義する! {
    /// ワールドまたは剛体の局所に属する力(ニュートンの3成分)。
    力, ニュートン
}

/// 次元の合成: 力 × 時間 = 衝撃。
impl<空間種: 空間> Mul<秒> for 力<空間種> {
    type Output = 衝撃<空間種>;
    fn mul(self, 経過時間: 秒) -> 衝撃<空間種> {
        衝撃::内部から生成する(self.内部ベクトル() * 経過時間.値())
    }
}

impl<空間種: 空間> 変位<空間種> {
    /// 腕(この変位)に掛かる力が生む回転力 r × F。任意の点へ力を加えたときに剛体の側が回転力へ写す式である。
    pub fn 腕に掛かる力の回転力(&self, 力: 力<空間種>) -> 回転力<空間種> {
        回転力::内部から生成する(self.内部ベクトル().cross(力.内部ベクトル()))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::frame::space::ワールド;
    use crate::units::{ニュートンメートル, ニュートン秒, メートル};

    #[test]
    fn 力に時間を掛けると衝撃になり腕との外積は回転力になる() {
        let 力 = 力::<ワールド>::成分から生成する(ニュートン::生成する(0.0), ニュートン::生成する(3.0), ニュートン::生成する(0.0));
        assert_eq!((力 * 秒::生成する(2.0)).y(), ニュートン秒::生成する(6.0));
        let 腕 = 変位::成分から生成する(メートル::生成する(2.0), メートル::生成する(0.0), メートル::生成する(0.0));
        assert_eq!(腕.腕に掛かる力の回転力(力).z(), ニュートンメートル::生成する(6.0));
    }
}
