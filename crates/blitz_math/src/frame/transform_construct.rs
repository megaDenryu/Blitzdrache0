//! 変換の生成関数: 注視（look-at）・透視投影。
//! Vulkanのクリップ空間規約（深度0..1、Yは下向き）に合わせて構築する。

use glam::{Mat4, Vec3};

use super::position::位置;
use super::space::{クリップ, ビュー, ワールド, 光源クリップ};
use super::transform::変換;
use crate::units::{メートル, ラジアン};

impl 変換<ワールド, ビュー> {
    /// 視点位置から注視点を見るビュー変換を作る。上方向は+Yで固定する。
    pub fn 注視(視点位置: 位置<ワールド>, 注視点: 位置<ワールド>) -> Self {
        let 内部 = Mat4::look_at_rh(視点位置.内部ベクトル(), 注視点.内部ベクトル(), Vec3::Y);
        変換::内部から生成する(内部)
    }
}

impl 変換<ビュー, クリップ> {
    /// 縦視野角・アスペクト比・近遠クリップから透視投影変換を作る。
    ///
    /// 注意: glamの`perspective_rh`は深度0..1（Vulkan/D3D規約）のRH投影を返すが、
    /// NDCのYは上向きのままである。VulkanのNDCはYが下向きのため、
    /// Y成分を反転する行列を左から掛けて既定規約に合わせる。
    pub fn 透視投影(縦視野角: ラジアン, アスペクト比: f32, 近クリップ: メートル, 遠クリップ: メートル) -> Self {
        let 投影 = Mat4::perspective_rh(縦視野角.値(), アスペクト比, 近クリップ.値(), 遠クリップ.値());
        let y反転 = Mat4::from_scale(Vec3::new(1.0, -1.0, 1.0));
        変換::内部から生成する(y反転 * 投影)
    }
}

impl 変換<ビュー, 光源クリップ> {
    /// 方向光のシャドウマップ用の正射影(判断36)。ビュー空間原点を中心とした
    /// 直方体(横半幅・縦半幅・近クリップ〜遠クリップ)を光源クリップ空間へ写す。
    ///
    /// 注意: 透視投影と同じくglamの`orthographic_rh`は深度0..1のRH投影を返すが
    /// NDCのYは上向きのため、Y成分を反転してVulkanの規約に合わせる。
    pub fn 正射影(横半幅: メートル, 縦半幅: メートル, 近クリップ: メートル, 遠クリップ: メートル) -> Self {
        let 横半幅値 = 横半幅.値();
        let 縦半幅値 = 縦半幅.値();
        let 投影 = Mat4::orthographic_rh(-横半幅値, 横半幅値, -縦半幅値, 縦半幅値, 近クリップ.値(), 遠クリップ.値());
        let y反転 = Mat4::from_scale(Vec3::new(1.0, -1.0, 1.0));
        変換::内部から生成する(y反転 * 投影)
    }
}
