//! 射影へ加える1画素未満の平行移動と、その値域違反。
//!
//! 保持する量を正規化装置座標にそろえるのは、消費する2者(射影へ足す側と、深度から位置を戻す側)が
//! どちらもこの座標で足し引きするためである。画素のままで保つと、2者が別々の画素数で写した食い違いが
//! 起こりうる。画面の画素数を要るのは、画素の量から作るこの1箇所だけになる。
//! 参照: `_doc/設計/時間再構成.md`「判断a」

use std::fmt;

use glam::DVec2;

/// 射影へ加える1画素未満の平行移動。横は右が正、縦は下が正であり、Vulkanの正規化装置座標の向きにそろう。
/// 不変条件: 2成分とも有限であり、大きさは1画素ぶんの正規化装置座標の幅より小さい。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 画素内ずらし {
    正規化装置座標の横: f32,
    正規化装置座標の縦: f32,
}

impl 画素内ずらし {
    /// ずらしを加えない値。時間再構成を使わない世界と、ずらしの列を回す前の初期値がこれを使う。
    pub fn ずらさない() -> Self {
        Self {
            正規化装置座標の横: 0.0,
            正規化装置座標の縦: 0.0,
        }
    }

    /// 画素を単位とするずらしから作る。1画素の幅は正規化装置座標で2を画素数で割った値であるから、その倍率で写す。
    pub fn 画素から生成する(
        横画素: f32, 縦画素: f32, 横の画素数: u32, 縦の画素数: u32
    ) -> Result<Self, 画素内ずらしエラー> {
        Ok(Self {
            正規化装置座標の横: 一成分を写す(横画素, 横の画素数)?,
            正規化装置座標の縦: 一成分を写す(縦画素, 縦の画素数)?,
        })
    }

    pub fn 正規化装置座標の横(self) -> f32 {
        self.正規化装置座標の横
    }

    pub fn 正規化装置座標の縦(self) -> f32 {
        self.正規化装置座標の縦
    }
}

/// 1成分ぶんの写し。単精度への丸めが入るのはここだけであり、倍精度で組み立ててから狭める。
fn 一成分を写す(画素: f32, 画素数: u32) -> Result<f32, 画素内ずらしエラー> {
    if !画素.is_finite() || 画素.abs() >= 1.0 {
        return Err(画素内ずらしエラー::一画素未満でない(画素));
    }
    if 画素数 == 0 {
        return Err(画素内ずらしエラー::画素数が零);
    }
    Ok(DVec2::splat(2.0 * f64::from(画素) / f64::from(画素数)).as_vec2().x)
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 画素内ずらしエラー {
    一画素未満でない(f32),
    画素数が零,
}

impl fmt::Display for 画素内ずらしエラー {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::一画素未満でない(値) => write!(formatter, "画素内ずらしの成分が有限かつ1画素未満でない: {値}"),
            Self::画素数が零 => write!(formatter, "画素内ずらしを写す画面の画素数が零である"),
        }
    }
}

impl std::error::Error for 画素内ずらしエラー {}
