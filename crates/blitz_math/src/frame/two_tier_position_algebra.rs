//! 二段の位置の演算。担当するのは、変位を足すこと(細かい位置へ足して繰り上げる)、二段の位置と位置のあいだの差
//! (粗い位置の差 + 細かい位置の差の順で求め、途中で単精度の世界座標へ潰さない)、粗い位置の表現の刻み幅の向きへの射影
//! (解けたと見なす許容差を導く材料)である。型の定義(`two_tier_position.rs`)と分けるのは、あちらが2段の不変条件と
//! 繰り上げの算法を持つ型の定義であり、こちらが位置の利用者(予測・補正・拘束違反・速度の再構成)が要る演算だからである。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断3」

use std::ops::Sub;

use super::direction::方向;
use super::displacement::変位;
use super::global_world_position::大域ワールド位置;
use super::position::位置;
use super::space::空間;
use super::two_tier_position::二段の位置;
use crate::units::{メートル, 大域メートル};

impl<空間種: 空間> 二段の位置<空間種> {
    /// 変位のぶんだけ動かした二段の位置。変位は細かい位置へ足し、和を保ったまま繰り上げる(誤差なし加算を2段に重ね、加算の丸めを1e-13メートルの桁に抑える)。
    pub fn 変位を足す(&self, 変位: 変位<空間種>) -> Self {
        Self::変位を足して繰り上げる(self.粗い内部ベクトル(), self.細かい内部ベクトル(), 変位.内部ベクトル())
    }

    /// 衝突の問い合わせの基準原点を選ぶために読む粗い位置。細かい位置を捨てる畳む口ではなく、この値と二段の位置の差
    /// (`二段の位置 − 位置`)が細かい位置をそのまま保つ。見かけ上の世界位置としてCPUの物理へ渡してはならない
    /// (参照: `_doc/設計/剛体の状態と接触.md`「判断3」の衝突数学層へ形を渡す境界)。
    pub fn 基準原点を選ぶための粗い位置(&self) -> 位置<空間種> {
        位置::内部から生成する(self.粗い内部ベクトル())
    }

    /// 粗い位置と細かい位置の和を倍精度で評価した位置。2つの単精度の和は倍精度で厳密に表せるため、この口は情報を落とさない。
    /// 計器と倍精度の参照計算が読む口であり、単精度へ狭めて物理へ戻す経路は作らない。
    pub fn 倍精度で評価した位置(&self) -> 大域ワールド位置 {
        let (粗い, 細かい) = (self.粗い内部ベクトル(), self.細かい内部ベクトル());
        大域ワールド位置::生成する(
            大域メートル::生成する(f64::from(粗い.x) + f64::from(細かい.x)),
            大域メートル::生成する(f64::from(粗い.y) + f64::from(細かい.y)),
            大域メートル::生成する(f64::from(粗い.z) + f64::from(細かい.z)),
        )
    }

    /// 粗い位置の各成分の表現の刻み幅を、向きの成分の絶対値で重み付けて足した長さ Σ_k |n_k| ulp(x_粗,k)。
    /// 解けたと見なす許容差(2つの点の単精度の世界座標の量子化)を導く材料であり、細かい位置の刻みではなく粗い位置の刻みを数える。
    pub fn 向きへ射影した粗い位置の表現の刻み幅(&self, 向き: 方向<空間種>) -> メートル {
        let 粗い = self.粗い内部ベクトル();
        メートル::生成する(粗い.x).表現の刻み幅() * 向き.x().abs()
            + メートル::生成する(粗い.y).表現の刻み幅() * 向き.y().abs()
            + メートル::生成する(粗い.z).表現の刻み幅() * 向き.z().abs()
    }
}

/// 二段の位置から二段の位置を引くと変位になる。`右辺`から`self`へ向かう変位であり、粗い位置の差と細かい位置の差を別々に求めてから足す。
impl<空間種: 空間> Sub for 二段の位置<空間種> {
    type Output = 変位<空間種>;

    fn sub(self, 右辺: Self) -> 変位<空間種> {
        変位::内部から生成する(
            (self.粗い内部ベクトル() - 右辺.粗い内部ベクトル()) + (self.細かい内部ベクトル() - 右辺.細かい内部ベクトル()),
        )
    }
}

/// 二段の位置から単精度の位置を引くと変位になる。単精度の位置は細かい位置が零の二段の位置として扱う。
impl<空間種: 空間> Sub<位置<空間種>> for 二段の位置<空間種> {
    type Output = 変位<空間種>;

    fn sub(self, 右辺: 位置<空間種>) -> 変位<空間種> {
        変位::内部から生成する((self.粗い内部ベクトル() - 右辺.内部ベクトル()) + self.細かい内部ベクトル())
    }
}

/// 単精度の位置から二段の位置を引くと変位になる。`右辺`(二段)から`self`へ向かう変位である。
impl<空間種: 空間> Sub<二段の位置<空間種>> for 位置<空間種> {
    type Output = 変位<空間種>;

    fn sub(self, 右辺: 二段の位置<空間種>) -> 変位<空間種> {
        変位::内部から生成する((self.内部ベクトル() - 右辺.粗い内部ベクトル()) - 右辺.細かい内部ベクトル())
    }
}
