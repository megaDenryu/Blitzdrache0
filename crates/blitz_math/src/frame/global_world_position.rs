//! f64大域ワールド位置からf32へ狭める唯一の変換境界。狭める先はカメラ大域原点を基準にしたカメラ相対位置と、
//! 描画の基準原点を基準にしたワールド位置の2つであり、どちらも同じ有限性とf32範囲の検査を通る。

use glam::DVec3;

use super::camera_relative_position::{カメラ相対位置, 座標変換エラー};
use super::position::位置;
use super::space::ワールド;
use crate::units::{メートル, 大域メートル};

#[derive(Debug, Clone, Copy, PartialEq)]
#[repr(transparent)]
pub struct 大域ワールド位置(DVec3);

impl 大域ワールド位置 {
    pub fn 生成する(x: 大域メートル, y: 大域メートル, z: 大域メートル) -> Self {
        Self(DVec3::new(x.値(), y.値(), z.値()))
    }

    /// 世界の原点。所有チャンクを持たない対象と、大域位置を持たない値の基準として使う。
    pub fn 原点() -> Self {
        Self(DVec3::ZERO)
    }

    pub fn 局所ワールド位置から生成する(位置: 位置<ワールド>) -> Self {
        Self(DVec3::new(f64::from(位置.x().値()), f64::from(位置.y().値()), f64::from(位置.z().値())))
    }

    /// 成分ごとに大域位置を足す。世界全体へ同じ平行移動を加える原点移動不変性の検査で使う。
    pub fn 平行移動する(self, ずれ: Self) -> Self {
        Self(self.0 + ずれ.0)
    }

    /// 相手の位置の側へ係数ぶん寄せた位置。0でこの位置そのもの、1で相手の位置になる。
    /// 描画補間が現在の確定値から前の確定値の側へ戻すのに使う(参照: `_doc/設計/時間の規律.md`「判断6」)。
    ///
    /// 注意: 係数0でこの位置を1ビットも変えずに返すことが、フレーム数の決まった実行の絵を補間の導入前と
    /// 一致させる根拠である。2つの位置へ重みを掛けて足す形も、差へ0を掛けた値を足す形もこれを満たさない。
    /// 後者が満たさないのは負のゼロがあるためである。成分が-0.0でその成分の相手が正のとき、差は正、差へ0を
    /// 掛けた値は+0.0、-0.0に+0.0を足した値は+0.0になり、符号のビットが落ちる。係数0をそのまま返す枝で塞ぐ。
    pub fn 相手の側へ係数ぶん寄せる(self, 相手: Self, 係数: f32) -> Self {
        if 係数 == 0.0 {
            return self;
        }
        Self(self.0 + (相手.0 - self.0) * f64::from(係数))
    }

    pub fn カメラ相対へ変換する(self, カメラ原点: Self) -> Result<カメラ相対位置, 座標変換エラー> {
        Ok(カメラ相対位置::内部から生成する(self.f32へ狭めた差分を求める(カメラ原点)?))
    }

    /// 基準の大域位置を原点とする局所ワールド位置へ狭める。動く個体の変換を描画の基準原点からの相対で表すときと、
    /// 大域位置をカメラの注視点(局所ワールド位置)へ写すときの両方が使う。
    /// カメラ相対位置と別の型を返すのは、引く相手がカメラ大域原点ではないためである。カメラ大域原点を引いた値を
    /// 個体の変換に使うと、その個体がカメラの動きに引きずられて動く。
    pub fn 局所ワールド位置へ狭める(self, 基準の大域位置: Self) -> Result<位置<ワールド>, 座標変換エラー> {
        let 差分 = self.f32へ狭めた差分を求める(基準の大域位置)?;
        Ok(位置::生成する(
            メートル::生成する(差分.x),
            メートル::生成する(差分.y),
            メートル::生成する(差分.z),
        ))
    }

    fn f32へ狭めた差分を求める(self, 基準: Self) -> Result<glam::Vec3, 座標変換エラー> {
        let 差分 = self.0 - 基準.0;
        if !差分.is_finite() {
            return Err(座標変換エラー::非有限値);
        }
        if 差分.abs().max_element() > f64::from(f32::MAX) {
            return Err(座標変換エラー::F32範囲外);
        }
        Ok(差分.as_vec3())
    }

    pub fn x(&self) -> 大域メートル {
        大域メートル::生成する(self.0.x)
    }

    pub fn y(&self) -> 大域メートル {
        大域メートル::生成する(self.0.y)
    }

    pub fn z(&self) -> 大域メートル {
        大域メートル::生成する(self.0.z)
    }
}
