//! 空間に属する回転力。成分はニュートンメートルであり、回転力 × 秒 = 回転衝撃の次元の合成を持つ。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断5」「判断6」。

use std::ops::Mul;

use super::angular_impulse::回転衝撃;
use super::space::空間;
use super::vector_quantity::三成分の量を定義する;
use crate::units::{ニュートンメートル, 秒};

三成分の量を定義する! {
    /// ワールドまたは剛体の局所に属する回転力(ニュートンメートルの3成分)。向きが回転の軸、長さが回そうとする強さである。
    回転力, ニュートンメートル
}

/// 次元の合成: 回転力 × 時間 = 回転衝撃。
impl<空間種: 空間> Mul<秒> for 回転力<空間種> {
    type Output = 回転衝撃<空間種>;
    fn mul(self, 経過時間: 秒) -> 回転衝撃<空間種> {
        回転衝撃::内部から生成する(self.内部ベクトル() * 経過時間.値())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::frame::space::ワールド;
    use crate::units::ニュートンメートル秒;

    #[test]
    fn 回転力に時間を掛けると回転衝撃になる() {
        let 回転力 = 回転力::<ワールド>::成分から生成する(
            ニュートンメートル::生成する(4.0),
            ニュートンメートル::生成する(0.0),
            ニュートンメートル::生成する(0.0),
        );
        assert_eq!((回転力 * 秒::生成する(0.25)).x(), ニュートンメートル秒::生成する(1.0));
    }
}
