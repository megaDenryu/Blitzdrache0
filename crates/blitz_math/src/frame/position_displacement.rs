//! 位置と変位の往復。位置から位置を引くと変位になり、位置へ変位を足すと位置になる。
//!
//! 変位そのものの定義から分けているのは、こちらが位置の側の口であり、位置の型を触るためである。
//! 位置に演算を足しても変位の定義は増えない。変わる理由が別である。

use std::ops::Sub;

use super::displacement::変位;
use super::position::位置;
use super::space::空間;

impl<空間種: 空間> 位置<空間種> {
    /// 変位のぶんだけ動かした位置。
    pub fn 変位を足す(&self, 変位: 変位<空間種>) -> Self {
        Self::内部から生成する(self.内部ベクトル() + 変位.内部ベクトル())
    }

    /// 空間の原点からこの位置までの変位。位置を変位として扱いたい場面の唯一の入口である。
    pub fn 原点からの変位(&self) -> 変位<空間種> {
        変位::内部から生成する(self.内部ベクトル())
    }
}

/// 位置から位置を引くと変位になる。`右辺`から`self`へ向かう変位であり、`右辺.変位を足す(差)`が`self`に戻る。
impl<空間種: 空間> Sub for 位置<空間種> {
    type Output = 変位<空間種>;

    fn sub(self, 右辺: Self) -> 変位<空間種> {
        変位::内部から生成する(self.内部ベクトル() - 右辺.内部ベクトル())
    }
}
