//! 空間に属する逆慣性テンソル(重心まわりの逆慣性の対称半正定値3×3行列)。主軸と逆主慣性から I⁻¹ = P diag(J⁻¹) Pᵀ で組む。
//! XPBDの姿勢自由度が読む量(一般化逆質量の回転の寄与・乗数から回転への写し・回転衝撃から角速度への写し)をメソッドで持ち、行列はこの型の内側に閉じる。
//! 零のテンソルは動かせない自由度(静的・運動学的)の実効の重みであり、質量の正本を0で表す意味ではない。
//! 参照: `_doc/設計/剛体の状態と接触.md`「判断4」「判断9」。

use std::fmt;
use std::marker::PhantomData;

use glam::Mat3;

use super::angular_impulse::回転衝撃;
use super::angular_velocity::角速度;
use super::direction::方向;
use super::displacement::変位;
use super::rotation::クォータニオン;
use super::rotation_vector::回転ベクトル;
use super::space::空間;
use crate::units::{キログラムメートル, キログラム平方メートル, 逆キログラム, 逆キログラム平方メートル};

#[repr(transparent)]
pub struct 逆慣性テンソル<空間種> {
    内部: Mat3,
    _空間: PhantomData<空間種>,
}

impl<空間種: 空間> 逆慣性テンソル<空間種> {
    /// 主軸(主軸座標からこの空間への回転)と逆主慣性の3値から I⁻¹ = P diag(J⁻¹) Pᵀ を組む。
    pub fn 主軸と逆主慣性から生成する<軸空間: 空間>(
        主軸: &クォータニオン<軸空間, 空間種>,
        逆主慣性: [逆キログラム平方メートル; 3],
    ) -> Self {
        let 回転 = Mat3::from_quat(主軸.内部クォータニオン());
        let 対角 = Mat3::from_diagonal(glam::Vec3::new(逆主慣性[0].値(), 逆主慣性[1].値(), 逆主慣性[2].値()));
        Self::内部から生成する(回転 * 対角 * 回転.transpose())
    }

    /// 動かせない自由度の実効の重み。
    pub fn 零() -> Self {
        Self::内部から生成する(Mat3::ZERO)
    }

    /// 角速度の変化 Δω = I⁻¹ L。
    pub fn 回転衝撃を角速度へ写す(&self, 回転衝撃: 回転衝撃<空間種>) -> 角速度<空間種> {
        角速度::内部から生成する(self.内部 * 回転衝撃.内部ベクトル())
    }

    /// 腕 r の点に向き n で作用する拘束の一般化逆質量の回転の寄与 (r × n)ᵀ I⁻¹ (r × n)。単位は毎キログラムであり、逆質量へそのまま足せる。
    pub fn 腕と向きの一般化逆質量の寄与(&self, 腕: 変位<空間種>, 向き: 方向<空間種>) -> 逆キログラム {
        let 外積 = 腕.内部ベクトル().cross(向き.内部ベクトル());
        逆キログラム::生成する(外積.dot(self.内部 * 外積))
            .unwrap_or_else(|誤り| panic!("逆慣性は半正定値で腕と向きは有限であるはずの不変条件の破れ: {誤り}"))
    }

    /// 腕 r の点に向き n で作用する拘束の一般化逆質量の回転の寄与の上界 |(I⁻¹ (r × n)) × r|。単位は毎キログラムである。
    /// 寄与そのものは (r × n)ᵀ I⁻¹ (r × n) = ((I⁻¹ (r × n)) × r)·n であり、向きへの射影を大きさで置き換えたこの値を超えない。
    /// 姿勢の補正を有限回転として適用すると腕の先は弦を描き、その長さは1次の接線の変位の長さ以下であるため、
    /// 乗数の増分1あたりに腕の先がどの向きへ実際に動く長さもこの値で上から抑えられる(判断12の1細分の長さの管理が読む)。
    pub fn 腕と向きの一般化逆質量の回転の寄与の上界(
        &self, 腕: 変位<空間種>, 向き: 方向<空間種>
    ) -> 逆キログラム {
        let 外積 = 腕.内部ベクトル().cross(向き.内部ベクトル());
        逆キログラム::生成する((self.内部 * 外積).cross(腕.内部ベクトル()).length())
            .unwrap_or_else(|誤り| panic!("逆慣性は半正定値で腕と向きは有限であるはずの不変条件の破れ: {誤り}"))
    }

    /// 回転だけに作用する拘束の一般化逆質量 nᵀ I⁻¹ n。単位は毎キログラム平方メートルである。
    pub fn 向きの一般化逆質量(&self, 向き: 方向<空間種>) -> 逆キログラム平方メートル {
        let n = 向き.内部ベクトル();
        逆キログラム平方メートル::生成する(n.dot(self.内部 * n))
            .unwrap_or_else(|誤り| panic!("逆慣性は半正定値で向きは有限であるはずの不変条件の破れ: {誤り}"))
    }

    /// 腕 r の点に向き n で大きさ λ の位置の乗数が作用したときの回転 I⁻¹ (r × (λ n))。姿勢の微小回転の更新へ渡す。
    pub fn 腕に作用する乗数の回転(
        &self, 腕: 変位<空間種>, 向き: 方向<空間種>, 乗数: キログラムメートル
    ) -> 回転ベクトル<空間種> {
        let 外積 = 腕.内部ベクトル().cross(向き.内部ベクトル() * 乗数.値());
        回転ベクトル::内部から生成する(self.内部 * 外積)
    }

    /// 向き n で大きさ λ の回転の乗数が作用したときの回転 I⁻¹ (λ n)。回転だけに作用する拘束の補正である。
    pub fn 向きに作用する回転の乗数の回転(
        &self, 向き: 方向<空間種>, 乗数: キログラム平方メートル
    ) -> 回転ベクトル<空間種> {
        回転ベクトル::内部から生成する(self.内部 * (向き.内部ベクトル() * 乗数.値()))
    }

    pub(crate) fn 内部行列(&self) -> Mat3 {
        self.内部
    }

    pub(crate) fn 内部から生成する(内部: Mat3) -> Self {
        Self {
            内部, _空間: PhantomData
        }
    }
}

// 手動実装: deriveは幻影型パラメータ自身にも境界を要求するが、空間種は実行時表現を持たない。
impl<空間種> Clone for 逆慣性テンソル<空間種> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<空間種> Copy for 逆慣性テンソル<空間種> {}

impl<空間種> PartialEq for 逆慣性テンソル<空間種> {
    fn eq(&self, 相手: &Self) -> bool {
        self.内部 == 相手.内部
    }
}

impl<空間種> fmt::Debug for 逆慣性テンソル<空間種> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("逆慣性テンソル").field("内部", &self.内部).finish()
    }
}
