//! 回転を剛体の力学へ使うための操作。担当するのは、逆回転・微小回転による更新(正規化を含む)・単位四元数から回転ベクトルへの2つの写し・
//! 力学の量(角速度・回転力・回転衝撃・回転ベクトル・逆慣性テンソル)を回す操作である。
//! 合成と変位の回転(`rotation_compose.rs`)と分けるのは、あちらが描画と組み立てが使う一般の合成であり、こちらが剛体XPBDの積分と補正が要る演算だからである。
//! 正規化を更新の戻り値の生成に閉じ、呼び出し側が正規化を忘れられる経路を作らない(`_doc/設計/剛体の状態と接触.md`「判断3」)。

use glam::{Mat3, Quat, Vec3};

use super::angular_impulse::回転衝撃;
use super::angular_velocity::角速度;
use super::inverse_inertia_tensor::逆慣性テンソル;
use super::rotation::クォータニオン;
use super::rotation_vector::回転ベクトル;
use super::space::空間;
use super::torque::回転力;

// 回転ベクトルの長さがこれより短い単位四元数は回転なしとして零の回転ベクトルへ写す(対数写像の0÷0を避ける。判断7)。
const 対数写像で軸が定まる最小のベクトル部の長さ: f32 = 1.0e-8;

impl<入力空間: 空間, 出力空間: 空間> クォータニオン<入力空間, 出力空間> {
    /// 逆向きの回転。出力空間から入力空間へ戻す。
    pub fn 逆回転(&self) -> クォータニオン<出力空間, 入力空間> {
        クォータニオン::内部から生成する(self.内部クォータニオン().inverse())
    }

    /// 出力空間の微小な回転 θ で更新した回転 q + (1/2)·(θ_四元数 ⊗ q) を正規化して返す。θ_四元数 = (θx, θy, θz, 0) である。
    /// 姿勢の積分(θ = h ω)と拘束の補正(θ = I⁻¹ (r × Δλ n))の両方がこの1つの式を読む。
    pub fn 微小回転で更新する(&self, 回転: 回転ベクトル<出力空間>) -> Self {
        Self::内部から生成する(self.正規化しない微小回転の更新(回転).normalize())
    }

    /// 正規化を外した更新。長さが1から離れることの反証だけが読む。
    #[cfg(test)]
    pub(crate) fn 正規化せずに微小回転で更新する(&self, 回転: 回転ベクトル<出力空間>) -> Self {
        Self::内部から生成する(self.正規化しない微小回転の更新(回転))
    }

    fn 正規化しない微小回転の更新(&self, 回転: 回転ベクトル<出力空間>) -> Quat {
        let q = self.内部クォータニオン();
        let 半分の回転 = 回転.内部ベクトル() * 0.5;
        let 増分 = Quat::from_xyzw(半分の回転.x, 半分の回転.y, 半分の回転.z, 0.0) * q;
        Quat::from_xyzw(q.x + 増分.x, q.y + 増分.y, q.z + 増分.z, q.w + 増分.w)
    }

    /// 微小な回転として読んだ回転ベクトル 2·vec(q)(実部が負なら符号を反転して短い弧を取る)。細分1本の回転は小さいため1次の形で足りる(判断9)。
    pub fn 微小回転として回転ベクトルへ(&self) -> 回転ベクトル<出力空間> {
        let q = self.短い弧の側();
        回転ベクトル::内部から生成する(q.xyz() * 2.0)
    }

    /// 対数写像で読んだ回転ベクトル (2·atan2(|vec(q)|, re(q)) ÷ |vec(q)|)·vec(q)。半回転までの任意の大きさの回転に使う(判断7)。
    pub fn 対数写像で回転ベクトルへ(&self) -> 回転ベクトル<出力空間> {
        let q = self.短い弧の側();
        let ベクトル部の長さ = q.xyz().length();
        if ベクトル部の長さ < 対数写像で軸が定まる最小のベクトル部の長さ {
            return 回転ベクトル::零();
        }
        回転ベクトル::内部から生成する(q.xyz() * (2.0 * ベクトル部の長さ.atan2(q.w) / ベクトル部の長さ))
    }

    fn 短い弧の側(&self) -> Quat {
        let q = self.内部クォータニオン();
        if q.w < 0.0 { -q } else { q }
    }

    pub fn 角速度を回す(&self, 角速度: 角速度<入力空間>) -> 角速度<出力空間> {
        角速度::内部から生成する(self.内部クォータニオン() * 角速度.内部ベクトル())
    }

    pub fn 回転力を回す(&self, 回転力: 回転力<入力空間>) -> 回転力<出力空間> {
        回転力::内部から生成する(self.内部クォータニオン() * 回転力.内部ベクトル())
    }

    pub fn 回転衝撃を回す(&self, 回転衝撃: 回転衝撃<入力空間>) -> 回転衝撃<出力空間> {
        回転衝撃::内部から生成する(self.内部クォータニオン() * 回転衝撃.内部ベクトル())
    }

    pub fn 回転ベクトルを回す(&self, 回転: 回転ベクトル<入力空間>) -> 回転ベクトル<出力空間> {
        回転ベクトル::内部から生成する(self.内部クォータニオン() * 回転.内部ベクトル())
    }

    /// 逆慣性テンソルを出力空間へ写す R I⁻¹ Rᵀ。ワールドの逆慣性は姿勢が変わるたびに変わるため状態に持たず、使う場所でこれを呼ぶ(判断4)。
    pub fn 逆慣性テンソルを回す(&self, 逆慣性: &逆慣性テンソル<入力空間>) -> 逆慣性テンソル<出力空間> {
        let 回転 = Mat3::from_quat(self.内部クォータニオン());
        逆慣性テンソル::内部から生成する(回転 * 逆慣性.内部行列() * 回転.transpose())
    }

    /// 回転の四元数が単位長からどれだけ離れているか。検査が正規化の維持を見るために読む。
    pub fn 長さの1からのずれ(&self) -> f32 {
        (self.内部クォータニオン().length() - 1.0).abs()
    }

    /// 回転ベクトル(向きが軸、長さが角)が表す回転。対数写像の逆であり、検査が既知の回転を組み立てるときと運動学的剛体の配置を進めるときに使う。
    pub fn 回転ベクトルから生成する(回転: 回転ベクトル<出力空間>) -> Self {
        let ベクトル: Vec3 = 回転.内部ベクトル();
        let 角 = ベクトル.length();
        if 角 < 対数写像で軸が定まる最小のベクトル部の長さ {
            return Self::内部から生成する(Quat::IDENTITY);
        }
        Self::内部から生成する(Quat::from_axis_angle(ベクトル / 角, 角))
    }
}
