//! 大域ワールド位置を相手の側へ寄せる演算の試験。担当するのは、係数0でこの位置が1ビットも変わらないことと、
//! 係数1で相手の位置へ届くことの2つを固定することである。
//!
//! 前者を落とすと、フレーム数の決まった実行の絵が補間の導入だけで変わる。後者を落とすと、蓄積の余りが
//! 基本刻みに達した描画で個体が1刻みぶん手前に取り残される。参照: `_doc/設計/時間の規律.md`「判断6」。

use super::global_world_position::大域ワールド位置;
use crate::units::大域メートル;

fn 位置(東へ: f64, 天頂へ: f64, 南へ: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(東へ), 大域メートル::生成する(天頂へ), 大域メートル::生成する(南へ))
}

/// 成分の値でなくビットの並びで見るのは、`PartialEq`が正のゼロと負のゼロを等しいと扱うためである。
fn 成分のビット(対象: 大域ワールド位置) -> [u64; 3] {
    [対象.x().値().to_bits(), 対象.y().値().to_bits(), 対象.z().値().to_bits()]
}

/// 反証: 差へ係数を掛けて足す形だけで書くと、負のゼロの成分が正のゼロへ変わる。差が正、それへ0を掛けた値が
/// 正のゼロ、負のゼロに正のゼロを足した値が正のゼロになるためである。
#[test]
fn 係数0では負のゼロの成分も符号のビットまで変わらない() {
    let 現在 = 位置(-0.0, -0.0, -0.0);
    assert_eq!(
        成分のビット(現在.相手の側へ係数ぶん寄せる(位置(10.0, 20.0, 30.0), 0.0)),
        成分のビット(現在)
    );
}

#[test]
fn 係数0では負でないゼロを含む位置も1ビットも変わらない() {
    let 現在 = 位置(7.5, 0.0, -3.25);
    assert_eq!(
        成分のビット(現在.相手の側へ係数ぶん寄せる(位置(10.0, 20.0, 30.0), 0.0)),
        成分のビット(現在)
    );
}

#[test]
fn 係数1では相手の位置へ届く() {
    assert_eq!(
        位置(-0.0, 1.0, 2.0).相手の側へ係数ぶん寄せる(位置(10.0, 20.0, 30.0), 1.0),
        位置(10.0, 20.0, 30.0)
    );
}

#[test]
fn 係数が半分では2つの位置の中点になる() {
    assert_eq!(
        位置(0.0, 0.0, 0.0).相手の側へ係数ぶん寄せる(位置(10.0, 20.0, 30.0), 0.5),
        位置(5.0, 10.0, 15.0)
    );
}
