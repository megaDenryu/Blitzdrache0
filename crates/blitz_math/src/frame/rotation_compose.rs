//! 回転の合成と、回転を量へ適用する操作、および生値の出口。
//!
//! 回転そのものの定義から分けているのは、定義が「どういう値か」を持つのに対し、こちらが「その値で何をするか」を持つためである。
//! 操作を足しても定義は増えない。変わる理由が別である。

use super::direction::方向;
use super::displacement::変位;
use super::rotation::クォータニオン;
use super::space::空間;

impl<入力空間: 空間, 中間空間: 空間> クォータニオン<入力空間, 中間空間> {
    /// この回転で回してから、次の回転で回す合成。入力空間から次の出力空間への回転になる。
    /// 型が合うときだけコンパイルが通るため、掛け順の取り違えがここで落ちる。
    pub fn 続けて回す<出力空間: 空間>(
        &self,
        次: &クォータニオン<中間空間, 出力空間>,
    ) -> クォータニオン<入力空間, 出力空間> {
        クォータニオン::内部から生成する(次.内部クォータニオン() * self.内部クォータニオン())
    }
}

impl<入力空間: 空間, 出力空間: 空間> クォータニオン<入力空間, 出力空間> {
    /// 変位を回す。長さは変わらず向きだけが変わる。
    pub fn 変位を回す(&self, 変位: 変位<入力空間>) -> 変位<出力空間> {
        変位::内部から生成する(self.内部クォータニオン() * 変位.内部ベクトル())
    }

    /// 方向を回す。回転は長さを変えないため、単位長の不変条件は保たれる。
    pub fn 方向を回す(&self, 方向: 方向<入力空間>) -> 方向<出力空間> {
        方向::内部から生成する(self.内部クォータニオン() * 方向.内部ベクトル())
    }

    /// 生値の出口。x・y・z・wの順に並べる。実行時形式とGPU境界へ渡すときだけ使う。
    pub fn 成分(&self) -> [f32; 4] {
        self.内部クォータニオン().to_array()
    }
}
