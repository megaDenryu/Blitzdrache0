//! 数学DDD最小セット: 単位型・フレーム型を提供し、GPU境界でのみ生値を露出する。
//! あわせて、どの層からも使える決定的な混合関数をここが1つだけ持つ(写しが2つあると、同じ種から違う配置が出る)。
//!
//! 注意: glam型は公開APIに一切露出しない（re-exportも禁止）。座標系の混同・
//! 単位の取り違え・行列の掛け順ミスを型検査で防ぐことがこのクレートの存在意義。
//! 参照: `_doc/計画/ユビキタス言語.md`「数学DDDの語彙」。

#![forbid(unsafe_code)]

