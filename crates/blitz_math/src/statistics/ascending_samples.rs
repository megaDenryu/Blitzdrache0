//! 昇順に並べた標本列: パーセンタイル値を求められる形まで並べ替えた標本の並び。
//!
//! 裸の切片でなく型で持つのは、「昇順に並んでいる」ことがパーセンタイル値の前提だからである。
//! 切片のまま渡すと、並べ替えを忘れた列を渡しても型が通り、そのとき返る値は標本の並び順に依存した別物になる。
//! 並べ替えをこの型の入口の中で行うため、呼び出し側が忘れる余地そのものが無くなる。
//!
//! 借りた切片をその場で並べ替えて持つのは、標本が画面の全画素に及ぶ入口があり、写しを作る費用を避けるためである。

use super::percentile_rank::パーセンタイル順位;
use super::rank_index_rule::順位から添字を選ぶ規則;
use super::total_order::全順序で比べられる値;

/// 昇順に並べ替えた標本の並び。パーセンタイル値と最大値をここから採る。
pub struct 昇順に並べた標本列<'標本列, 標本>(&'標本列 [標本]);

impl<'標本列, 標本: 全順序で比べられる値> 昇順に並べた標本列<'標本列, 標本> {
    /// 受け取った切片をその場で昇順へ並べ替えてから借りる。
    pub fn 並べ替えて生成する(値一覧: &'標本列 mut [標本]) -> Self {
        値一覧.sort_by(標本::全順序で比べる);
        Self(値一覧)
    }

    /// 指定した順位のパーセンタイル値。標本が1件も無ければ値なしである。
    ///
    /// 補間せず、実在する標本のどれか1つをそのまま返す。補間した値は実際には観測されていない値であり、
    /// 計測の報告として読むときに「その時間で回ったフレームが在る」と読めなくなるためである。
    pub fn パーセンタイル値を求める(&self, 順位: パーセンタイル順位, 規則: 順位から添字を選ぶ規則) -> Option<標本> {
        if self.0.is_empty() {
            return None;
        }
        self.0.get(規則.昇順の添字を求める(self.0.len(), 順位)).copied()
    }

    /// 標本の件数。
    pub fn 件数(&self) -> usize {
        self.0.len()
    }

    /// 最も大きい標本。標本が1件も無ければ値なしである。
    pub fn 最大(&self) -> Option<標本> {
        self.0.last().copied()
    }

    /// 昇順に並んだ標本そのもの。平均や度数など、順位で選ぶ以外の集計がここから読む。
    pub fn 昇順の値一覧(&self) -> &[標本] {
        self.0
    }
}
