//! パーセンタイル順位から、昇順に並べた標本のどの添字を選ぶかの規則。
//!
//! 規則が1つでなく5つ在るのは、この層へ寄せる前の実装が入口ごとに別の式を書いており、その5つが同じ標本に対して
//! 違う添字を返すためである。どれか1つへ畳むと、既に計測して判定の閾値を決めた入口の値が動く。
//! どれを正とするかの裁定を受けるまで、入口ごとの現在の値を変えずに保つためにここで名前を与えて並べる。
//!
//! 規則は「何を基準に掛けるか」(最後の添字か、件数か)と「端数をどちらへ寄せるか」(切り上げ・四捨五入・切り捨て)の
//! 組み合わせである。同じ順位50に対して件数4の標本が返す添字は、上から順に2・2・1・1・2であり、一致しない。
//!
//! 添字を実数でなく整数の割り算で求めるのは、真の値がちょうど整数になる場合に浮動小数の丸めが1つ下の添字を
//! 選ぶ余地を残さないためである。順位は1000倍した整数で受け取るため、割る数も1000倍して釣り合わせる。

use super::percentile_rank::{パーセンタイル順位, 千倍した百分率の全体};

/// 昇順に並べた標本のどの添字をパーセンタイル値として選ぶかの規則。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 順位から添字を選ぶ規則 {
    /// 最後の添字に順位を掛け、端数を切り上げる。
    最後の添字を基準にした切り上げ,
    /// 最後の添字に順位を掛け、端数を四捨五入する。
    最後の添字を基準にした四捨五入,
    /// 最後の添字に順位を掛け、端数を切り捨てる。
    最後の添字を基準にした切り捨て,
    /// 件数に順位を掛けて端数を切り上げ、その1つ手前を選ぶ。
    件数を基準にした切り上げの1つ手前,
    /// 件数に順位を掛け、端数を切り捨てる。
    件数を基準にした切り捨て,
}

impl 順位から添字を選ぶ規則 {
    /// 昇順に並べた標本のうち、この規則が選ぶ添字。件数が0のときは0を返すため、呼び出し側が空を先に弾く。
    ///
    /// 注意: 返す添字は必ず最後の添字以下へ収める。順位100と件数を基準にする規則の組み合わせが標本の外を指すためである。
    pub(super) fn 昇順の添字を求める(self, 件数: usize, 順位: パーセンタイル順位) -> usize {
        let 最後の添字 = 件数.saturating_sub(1);
        let 件数を数へ = u64::try_from(件数).unwrap_or_else(|_| panic!("標本の件数がu64に収まらない: {件数}"));
        let 最後の添字を数へ = 件数を数へ.saturating_sub(1);
        let 千倍した百分率 = 順位.千倍した百分率();
        let 全体 = 千倍した百分率の全体;
        let 選んだ添字 = match self {
            Self::最後の添字を基準にした切り上げ => (千倍した百分率 * 最後の添字を数へ).div_ceil(全体),
            Self::最後の添字を基準にした四捨五入 => (千倍した百分率 * 最後の添字を数へ + 全体 / 2) / 全体,
            Self::最後の添字を基準にした切り捨て => 千倍した百分率 * 最後の添字を数へ / 全体,
            Self::件数を基準にした切り上げの1つ手前 => (千倍した百分率 * 件数を数へ).div_ceil(全体).saturating_sub(1),
            Self::件数を基準にした切り捨て => 千倍した百分率 * 件数を数へ / 全体,
        };
        usize::try_from(選んだ添字.min(最後の添字を数へ)).unwrap_or(最後の添字)
    }
}
