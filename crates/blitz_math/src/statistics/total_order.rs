//! 標本を並べ替えるときの全順序。
//!
//! 並べ替えの比べ方をこの1つへ寄せるのは、同じ標本の列が入口ごとに違う順序へ並ぶことを防ぐためである。
//! 実数は非数を含むと大小が定まらないため、標準の`total_cmp`が与える全順序(非数を最も大きい側へ置く)を使う。
//! 非数を含む列のパーセンタイル値は意味を持たないが、非数を取り除くのは標本を採る側の責務であり、
//! ここで黙って捨てると取り除いたことが呼び出し側から見えなくなる。

use std::cmp::Ordering;

use crate::units::メートル;

/// 非数を含みうる値にも全順序を与える比べ方。並べ替えの順序を1つに保つためにこの層が持つ。
pub trait 全順序で比べられる値: Copy {
    /// この値と右辺の、全順序での大小。
    fn 全順序で比べる(&self, 右辺: &Self) -> Ordering;
}

impl 全順序で比べられる値 for f64 {
    fn 全順序で比べる(&self, 右辺: &Self) -> Ordering {
        self.total_cmp(右辺)
    }
}

impl 全順序で比べられる値 for u16 {
    fn 全順序で比べる(&self, 右辺: &Self) -> Ordering {
        self.cmp(右辺)
    }
}

impl 全順序で比べられる値 for メートル {
    fn 全順序で比べる(&self, 右辺: &Self) -> Ordering {
        self.値().total_cmp(&右辺.値())
    }
}
