//! パーセンタイル順位: 昇順に並べた標本の何パーセントの位置を指すかを表す、0以上100以下の百分率。
//!
//! 0から1までの割合でなく0から100までの百分率で持つのは、この2つの取り違えが実際に起きているためである。
//! 刻みの所要時間の分布は0.5と0.99の割合で、フレーム間隔の統計は50と95と99の百分率で同じものを指しており、
//! 裸の実数で受け渡すと片方の綴りをもう片方へ書き写した時点で100倍ずれる。
//!
//! 順位を整数でなく実数で持つのは、99.9パーセンタイル値のように整数でない順位を指す要求があるためである。
//! 内部では百分率を1000倍した整数で持ち、添字の計算を整数の割り算だけで行う。実数の割り算で添字を求めると、
//! 真の値がちょうど整数になる場合に浮動小数の丸めが1つ下の添字を選ぶ余地が残るためである。
//!
//! この内部表現の帰結として、受け取った百分率は0.001パーセント刻みへ丸めてから保つ。受け取った実数をそのまま
//! 覚える型ではなく、0.001パーセント刻みの順位を表す型である。丸め方は最も近い刻みへ寄せる形であり、
//! 99.9994は99.999へ、99.9996は100へ落ちる。同じ刻みへ落ちる2つの百分率は等しい順位になり、以後は区別できない。

/// 内部表現の刻み。百分率を1000倍して持つため、0.001パーセント刻みの順位まで指せる。
const 百分率にかける倍率: f64 = 1000.0;
/// 1000倍した百分率の全体。100パーセントがこの値に当たる。
pub(super) const 千倍した百分率の全体: u64 = 100_000;

/// 昇順に並べた標本の何パーセントの位置を指すかを表す、0.001パーセント刻みの順位。
///
/// 注意: 受け取った百分率をそのまま保たず、最も近い0.001パーセント刻みへ丸めて保つ。同じ刻みへ落ちる2つの
/// 百分率は等しい順位になる。0.001パーセントより細かい違いで添字を分けたい呼び出しは、この型では表せない。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct パーセンタイル順位(u32);

impl パーセンタイル順位 {
    /// 0以上100以下の百分率を、最も近い0.001パーセント刻みへ丸めてから順位にする。
    ///
    /// 注意: 範囲の外と非有限は呼び出し側の書き誤りであり、続く添字が標本の外を指すため、到達したらバグとして落とす。
    /// 注意: 丸めは黙って起きる。99.9996を渡すと、標本の最後を指す順位100が返る。
    pub fn 百分率から生成する(百分率: f32) -> Self {
        assert!(百分率.is_finite() && (0.0..=100.0).contains(&百分率), "パーセンタイル順位は0以上100以下の有限な百分率でなければならない: {百分率}");
        Self(千倍した百分率へ写す(f64::from(百分率)))
    }

    pub(super) fn 千倍した百分率(self) -> u64 {
        u64::from(self.0)
    }
}

/// 百分率を1000倍し、最も近い整数へ写す。
///
/// ワークスペースが数値の`as`キャストを禁じており、実数から整数への`TryFrom`も標準に無いため、
/// ビットの重みを大きい側から参照して求める。1000倍した百分率の全体が17ビットに収まることを使う。
fn 千倍した百分率へ写す(百分率: f64) -> u32 {
    let mut 残り = (百分率 * 百分率にかける倍率).round();
    let mut 整数 = 0_u32;
    for ビット in (0_u32..17).rev() {
        let 重み = 1_u32 << ビット;
        if 残り >= f64::from(重み) {
            整数 |= 重み;
            残り -= f64::from(重み);
        }
    }
    整数.min(u32::try_from(千倍した百分率の全体).unwrap_or(u32::MAX))
}
