//! 全称命題とは、量化の対象集合の全ての要素を束縛変数へ当てて本体が成り立つ、と主張する命題のことである。
//!
//! 存在命題と同じ3つ組(束縛変数・量化の対象集合・本体)を持つが、別の型にする。見た範囲から反例が得られる向きと、
//! 見ていない範囲に依る向きが存在命題と逆であり、中身を共有する型にすると検証器がどちらの判定を呼ぶべきかを型で決められなくなるためである。

use super::super::量化の語彙::{束縛変数, 量化の対象集合};
use super::命題;

/// 量化の対象集合の全ての要素を束縛変数へ当てて本体が成り立つ、という命題。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 全称命題 {
    束縛: 束縛変数,
    量化の対象集合: 量化の対象集合,
    本体: Box<命題>,
}

impl 全称命題 {
    /// 束縛変数と、要素が走る範囲と、要素ごとに真偽を問う本体から組む。
    pub fn 生成する(束縛: 束縛変数, 量化の対象集合: 量化の対象集合, 本体: 命題) -> Self {
        Self {
            束縛, 量化の対象集合, 本体: Box::new(本体)
        }
    }

    /// 量化の対象集合の要素を当てる変数。本体の中の項がこの変数を指す。
    pub fn 束縛(&self) -> &束縛変数 {
        &self.束縛
    }

    /// 束縛へ当てる要素が走る範囲。
    pub fn 量化の対象集合(&self) -> &量化の対象集合 {
        &self.量化の対象集合
    }

    /// 要素ごとに真偽を問う命題。
    pub fn 本体(&self) -> &命題 {
        &self.本体
    }

    /// 人が読む1行の表記。
    pub fn 表記(&self) -> String {
        format!("全ての?{}が{}について ({})", self.束縛.名前(), self.量化の対象集合.表記(), self.本体.表記())
    }
}
