//! 空の連言と空の選言を通常のAPIで作れないことを固定する試験。
//!
//! 空の連言は要求を1件も見ないまま証明済みになり、空の選言は否定の下で同じ偽の証明を作る。
//! `非空の命題一覧` のフィールドは私有であるため、値を作れる口はこのファイルが呼ぶ2つ(`生成する`と`先頭と残りから生成する`)だけである。
//! したがってこの2つがどちらも0件を作らないことを見れば、`命題::連言` と `命題::選言` の積載物が0件になる経路は残らない。

#![allow(clippy::unwrap_used)]

use crate::設計概念への参照;

use super::super::atom::{原子命題, 項};
use super::{命題, 非空の命題一覧, 非空の命題一覧の生成の失敗};

fn 原子1件() -> 命題 {
    命題::原子から組む(原子命題::マーカーを持つ {
        概念: 項::名指した概念(設計概念への参照::型として生成する("blitz_esca::traveler", "旅行者")),
        マーカー名: "Mエンティティ".to_string(),
    })
}

#[test]
fn 空の並びから連言を組もうとすると型付きエラーになる() {
    assert_eq!(命題::連言を組む(Vec::new()), Err(非空の命題一覧の生成の失敗::並びが空である));
}

#[test]
fn 空の並びから選言を組もうとすると型付きエラーになる() {
    assert_eq!(命題::選言を組む(Vec::new()), Err(非空の命題一覧の生成の失敗::並びが空である));
}

#[test]
fn 非空の命題一覧のどの生成の口も0件の並びを作らない() {
    assert_eq!(非空の命題一覧::生成する(Vec::new()), Err(非空の命題一覧の生成の失敗::並びが空である));
    assert_eq!(非空の命題一覧::生成する(vec![原子1件()]).unwrap().件数(), 1);
    assert_eq!(非空の命題一覧::先頭と残りから生成する(原子1件(), Vec::new()).件数(), 1);
    assert_eq!(非空の命題一覧::先頭と残りから生成する(原子1件(), vec![原子1件()]).件数(), 2);
}

#[test]
fn 一件以上の並びから組んだ連言は積載物をそのまま持つ() {
    let 連言 = 命題::連言を組む(vec![原子1件()]).unwrap();
    let 命題::連言(項一覧) = &連言 else {
        panic!("1件の並びから組んだ命題は連言でなければならない");
    };
    assert_eq!(項一覧.一覧(), vec![原子1件()].as_slice());
}
