//! 非空の命題一覧とは、1件以上の命題を持つことを型で保証した命題の並びのことである。
//!
//! 連言と選言の積載物と、推論規則の前提一覧がこの型である。空の並びを許すと、何も見ずに証明済みを作れる。
//! 数学の上で空の連言が真であることと、検証器のAPIが「意図せず空になった要求の集まり」を受理してよいことは別である。
//! `collect()` がたまたま0件を返した連言は、要求を1件も見ないまま証明済みになる。
//!
//! **選言も非空にする理由は連言との対称性ではない。** 空の選言は恒偽であり、否定の下に置くと、何も見ずに証明済みを作る。
//!
//! **`恒真`・`恒偽` の選択肢は置かない。** それを書く法則が現に1件も無いため、置けば呼び出し側の無い実装になる。
//! 恒真と恒偽を書く要求が実際に立った時点で足す。
//! 参照: `_doc/設計/設計オントロジー.md` 第7節。

use std::error::Error;
use std::fmt::{Display, Formatter, Result as 整形の結果};

use super::命題;

/// 1件以上の命題を持つ並び。空の並びからは生成できない。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 非空の命題一覧(Vec<命題>);

/// 非空の命題一覧を生成できなかった理由。
/// 派生マクロで書かないのは、このクレートの通常依存を `blitz_design` だけに限る依存の白リストが `thiserror` を許していないためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 非空の命題一覧の生成の失敗 {
    /// 渡された命題の並びが0件だった。
    並びが空である,
}

impl 非空の命題一覧 {
    /// 命題の並びから生成する。0件なら失敗を返す。`collect()` の結果のように、件数が書いた時点で決まらない並びはこの関数を通す。
    pub fn 生成する(項一覧: Vec<命題>) -> Result<Self, 非空の命題一覧の生成の失敗> {
        if 項一覧.is_empty() {
            return Err(非空の命題一覧の生成の失敗::並びが空である);
        }
        Ok(Self(項一覧))
    }

    /// 先頭の1件と残りの並びから生成する。先頭が在ることが書いた時点で決まっているため失敗しない。
    pub fn 先頭と残りから生成する(先頭: 命題, 残り: Vec<命題>) -> Self {
        let mut 項一覧 = vec![先頭];
        項一覧.extend(残り);
        Self(項一覧)
    }

    /// 持っている命題の並び。1件以上であることが型で保証されている。
    pub fn 一覧(&self) -> &[命題] {
        &self.0
    }

    /// 持っている命題の件数。1以上である。
    pub fn 件数(&self) -> usize {
        self.0.len()
    }
}

impl Display for 非空の命題一覧の生成の失敗 {
    fn fmt(&self, 整形先: &mut Formatter<'_>) -> 整形の結果 {
        match self {
            Self::並びが空である => write!(整形先, "命題の並びが0件である(連言・選言・推論規則の前提は1件以上の命題を持たなければならない)"),
        }
    }
}

impl Error for 非空の命題一覧の生成の失敗 {}
