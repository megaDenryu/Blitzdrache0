//! 含意命題とは、前件が成り立つならば後件も成り立つ、と主張する命題のことである。
//!
//! 前件と後件はどちらも同じ `命題` の型だが役が違う。名前の無い2つ組にすると取り違えても型が通るため、名前の付いた読み出しで分ける。

use super::命題;

/// 前件が成り立つならば後件も成り立つ、という命題。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 含意命題 {
    前件: Box<命題>,
    後件: Box<命題>,
}

impl 含意命題 {
    /// 前件と後件から組む。
    pub fn 生成する(前件: 命題, 後件: 命題) -> Self {
        Self {
            前件: Box::new(前件), 後件: Box::new(後件)
        }
    }

    /// 成り立つときだけ後件を問う側の命題。
    pub fn 前件(&self) -> &命題 {
        &self.前件
    }

    /// 前件が成り立つときに成り立つべき命題。
    pub fn 後件(&self) -> &命題 {
        &self.後件
    }

    /// 人が読む1行の表記。
    pub fn 表記(&self) -> String {
        format!("({}) ならば ({})", self.前件.表記(), self.後件.表記())
    }
}
