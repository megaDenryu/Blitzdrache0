//! ドメインの側が実装する、有限に数え上げられる領域の契約。
//!
//! **この契約は遷移関数・遷移パラメータ・規則のどれも名指さない。** それらはドメインのクレートの型であり、このクレートは
//! ドメインを知らない。規則と経過時間は、この契約を実装する型が自分のフィールドで持ち、`一回遷移する` の中で実物の遷移関数へ渡す。
//! したがってこのクレートが受け取るのは、状態とコマンドの数え上げと、1回の遷移を実際に呼んだ帰結と、
//! それらを設計概念の識別子として名指す口だけである。検証の側が遷移の表を手で書き写すことが無いのは、遷移を作るのが
//! 実物の遷移関数だからである。
//!
//! 数え上げに `数え上げ` の型を置くのは、連続量を含む領域では取りうる値を全部並べられず、並べた標本を全件と呼べないためである
//! 参照: `crates/blitz_design_verification/src/coverage.rs`。
//! 参照: `_doc/設計/設計オントロジー.md` 第9節・第10節。

mod exploration;

pub use exploration::{探索の上限, 探索の結末, 領域から遷移モデルを組む};

use blitz_design::{Mイベント, Mコマンド, M状態};

use crate::設計概念の識別子;

/// 有限に数え上げられる領域とは、状態とコマンドを数え上げられ、実物の遷移関数を呼んで1回の遷移を行える、ドメインの側が実装する契約のことである。
pub trait 有限に数え上げられる領域 {
    /// この領域の状態。
    type 状態: M状態;
    /// この領域で主体が選ぶコマンド。
    type コマンド: Mコマンド;
    /// 1回の遷移で成立する過去の事実。
    type 出来事: Mイベント;

    /// 探索の起点になる状態の全件。
    fn 初期状態一覧(&self) -> Vec<Self::状態>;

    /// その状態で試すコマンドを数え上げる。連続量を含むなら標本として答える。
    fn 状態で試すコマンドを数え上げる(&self, 状態: &Self::状態) -> 数え上げ<Self::コマンド>;

    /// その状態へそのコマンドを与えて、実物の遷移関数を1回呼ぶ。
    fn 一回遷移する(&self, 状態: &Self::状態, コマンド: &Self::コマンド) -> 遷移の帰結<Self::状態, Self::出来事>;

    /// その状態を設計概念の識別子として名指す。同じ状態は常に同じ識別子へ写る。
    fn 状態を名指す(&self, 状態: &Self::状態) -> 設計概念の識別子;

    /// そのコマンドを設計概念の識別子として名指す。
    fn コマンドを名指す(&self, コマンド: &Self::コマンド) -> 設計概念の識別子;

    /// その出来事を設計概念の識別子として名指す。
    fn 出来事を名指す(&self, 出来事: &Self::出来事) -> 設計概念の識別子;

    /// この領域が遷移へ適用する規則を設計概念の識別子として名指す。遷移1件がどの規則の下で起きたかを記録に残すために要る。
    fn 規則を名指す(&self) -> 設計概念の識別子;
}

/// 取りうる値を数え上げた結末。
/// `連続量を含む標本` の `標本` は実際に試す値の並びであり、`連続量の説明` はどの量が連続であるかを人へ伝える文である。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 数え上げ<値> {
    /// 取りうる値を全部並べた。この領域についての全称の命題は証明済みになりうる。
    全件(Vec<値>),
    /// 連続量を含み全部は並べられないため、標本だけを並べた。この領域についての全称の命題は証明済みにならない。
    連続量を含む標本 { 標本: Vec<値>, 連続量の説明: String },
}

/// 実物の遷移関数を1回呼んだ帰結。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 遷移の帰結<状態, 出来事> {
    /// 遷移が成立し、遷移関数が返した次の状態と、そのとき成立した出来事の並びが定まった。
    成功 { 次の状態: 状態, 出来事一覧: Vec<出来事> },
    /// 遷移が成立しなかった。次の状態は採用されず、出来事は1件も成立しない。説明は何が成立しなかったかを人へ伝える文である。
    失敗 { 説明: String },
}

impl<値> 数え上げ<値> {
    /// 実際に試す値の並び。全件でも標本でも、試す並びはこの1つの口から取る。
    pub fn 試す値一覧(&self) -> &[値] {
        match self {
            Self::全件(一覧) => 一覧,
            Self::連続量を含む標本 { 標本, .. } => 標本,
        }
    }

    /// 連続量を含むならその説明。全件なら値なしである。
    pub fn 連続量の説明(&self) -> Option<&str> {
        match self {
            Self::全件(_) => None,
            Self::連続量を含む標本 { 連続量の説明, .. } => Some(連続量の説明),
        }
    }
}
