//! ドメインの側が実装する、有限に数え上げられる領域の契約。
//!
//! **この契約は状態遷移関数・状態遷移パラメータ・規則のどれも名指さない。** それらはドメインのクレートの型であり、このクレートは
//! ドメインを知らない。規則と経過時間は、この契約を実装する型が自分のフィールドで持ち、`一回の状態遷移を行う` の中で実物の状態遷移関数へ渡す。
//! したがってこのクレートが受け取るのは、状態とコマンドの数え上げと、1回の状態遷移を実際に呼んだ帰結と、
//! それらを設計概念の識別用情報として名指すメソッドだけである。検証の側が状態遷移の表を手で書き写すことが無いのは、状態遷移を作るのが
//! 実物の状態遷移関数だからである。
//!
//! 数え上げに `数え上げ` の型を置くのは、連続量を含む領域では取りうる値を全部並べられず、並べた標本を全件と呼べないためである
//! 参照: `crates/blitz_design_verification/src/coverage.rs`。
//!
//! **状態の識別用情報と状態の名指しを別のメソッドに分ける。** 識別用情報は探索が同じ状態かどうかを決める判断であり、
//! 名指しは命題と設計関係グラフがその状態を指す名前である。1つのメソッドで兼ねると、名前の都合が済みの集合の鍵になり、
//! 別の状態が黙って同じ1件として捨てられる。
//! **どちらも、互いに等しくない2つの値を同じ答えへ写してはならない。** 名指しは人が読む表示ではない。
//! 表示のために粗くした名前を名指しに使うと、探索が別物として辿った2つの状態が命題の層で同じ1件として引き当てられ、
//! Bしか起きていない状態遷移で `発生する(A)` が通る。人が読む粗い表記は、領域の側が名指しとは別に持つ。
//! **この契約は識別用情報も名指しも単射であることを領域へ要求しない。** 要求しても実装は守れるとは限らないため、
//! 異なる状態に同じ識別用情報が与えられたことを探索の側が検出し、その数え上げに `全件を数え上げた` を名乗らせない。異なる値に同じ名指しが与えられたことも同じ形で検出する
//! 参照: `crates/blitz_design_verification/src/domain/exploration/breadth_first.rs`。
//! 参照: `_doc/設計/設計オントロジー.md` 第9節・第10節。

mod exploration;

pub use exploration::{探索が組んだ状態遷移モデルと網羅性, 探索の上限, 状態遷移失敗結果の元の状態の食い違い, 領域から状態遷移モデルを組む};

use std::hash::Hash;

use blitz_design::{Mイベント, M状態, M状態遷移が受け取る命令};

use crate::設計概念の識別用情報;

/// 有限に数え上げられる領域とは、状態とコマンドを数え上げられ、実物の状態遷移関数を呼んで1回の状態遷移を行える、ドメインの側が実装する契約のことである。
pub trait 有限に数え上げられる領域 {
    /// この領域の状態。互いに等しいかを問えることを求めるのは、探索が識別用情報ごとの代表の状態と突き合わせて異なる状態に同じ識別用情報が与えられたことを検出するためである。
    type 状態: M状態 + PartialEq;
    /// この領域で状態遷移が受け取る命令(1つの選択か命令の組)。互いに等しいかを問えることを求めるのは、探索が名指しごとの代表と突き合わせて異なる値に同じ名指しが与えられたことを検出するためである。
    type コマンド: M状態遷移が受け取る命令 + PartialEq;
    /// 1回の状態遷移で成立する過去の宣言。互いに等しいかを問えることを求める理由はコマンドと同じである。
    type 出来事: Mイベント + PartialEq;
    /// この領域が状態の識別用情報を表すために選ぶ型。単精度のビットの並びのように、異なる状態を同じ値へ写さない写しを領域が選ぶ。
    type 状態の識別用情報: Eq + Hash;

    /// 探索の起点になる状態を数え上げる。連続量を含むなら標本として答える。
    /// コマンドの数え上げと同じ型で答えるのは、初期状態が代表の標本であることも、コマンドの標本と同じく網羅性を落とすためである。
    fn 初期状態を数え上げる(&self) -> 数え上げ<Self::状態>;

    /// その状態で試すコマンドを数え上げる。連続量を含むなら標本として答える。
    fn 状態で試すコマンドを数え上げる(&self, 状態: &Self::状態) -> 数え上げ<Self::コマンド>;

    /// その状態へそのコマンドを与えて、実物の状態遷移関数を1回呼ぶ。失敗のときは、状態遷移関数が状態遷移失敗結果に入れて返した元の状態をそのまま帰結へ入れる。
    /// 元の状態が受け取った状態と等しいかを領域の側で確かめない。確かめるのは探索である(`状態遷移失敗結果の元の状態の食い違い`)。
    fn 一回の状態遷移を行う(&self, 状態: &Self::状態, コマンド: &Self::コマンド) -> 状態遷移の帰結<Self::状態, Self::出来事>;

    /// その状態を識別用情報へ変換する。探索はこの値が同じ状態を同じ1件として扱う。
    fn 状態を識別用情報へ変換する(&self, 状態: &Self::状態) -> Self::状態の識別用情報;

    /// その状態を設計概念の識別用情報として名指す。同じ状態は常に同じ識別用情報へ写り、互いに等しくない2つの状態は別の識別用情報へ写る。
    /// 探索が同じ状態かどうかを決める判断にはこの名前を使わない。人が読む粗い表記はこのメソッドで作らない。
    fn 状態を名指す(&self, 状態: &Self::状態) -> 設計概念の識別用情報;

    /// そのコマンドを設計概念の識別用情報として名指す。互いに等しくない2つのコマンドは別の識別用情報へ写る。
    fn コマンドを名指す(&self, コマンド: &Self::コマンド) -> 設計概念の識別用情報;

    /// その出来事を設計概念の識別用情報として名指す。互いに等しくない2つの出来事は別の識別用情報へ写る。
    fn 出来事を名指す(&self, 出来事: &Self::出来事) -> 設計概念の識別用情報;

    /// この領域が状態遷移へ適用する規則を設計概念の識別用情報として名指す。状態遷移1件がどの規則の下で起きたかを状態遷移の材料へ残すために要る。
    fn 規則を名指す(&self) -> 設計概念の識別用情報;
}

/// 取りうる値を数え上げた結果。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 数え上げ<値> {
    /// 取りうる値を全部並べた。この領域についての全称の命題は証明済みになりうる。
    全件(Vec<値>),
    /// 連続量を含み全部は並べられないため、標本だけを並べた。この領域についての全称の命題は証明済みにならない。
    連続量を含む標本 {
        /// 実際に試す値の並び。取りうる値の全部ではない。
        標本: Vec<値>,
        /// どの量が連続であるかを人へ伝える文。数え上げの網羅性の表記を経て未決定の理由の文へ入る。
        連続量の説明: String,
    },
}

/// 実物の状態遷移関数を1回呼んだ帰結。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 状態遷移の帰結<状態, 出来事> {
    /// 状態遷移が成立し、状態遷移関数が返した次の状態と、そのとき成立した出来事の並びが定まった。
    成功 {
        /// 状態遷移関数が返した、この状態遷移の後の状態。
        次の状態: 状態,
        /// この状態遷移で実際に成立した過去の宣言の並び。
        出来事一覧: Vec<出来事>,
    },
    /// 状態遷移が成立しなかった。次の状態は採用されず、出来事は1件も成立しない。説明は何が成立しなかったかを人へ伝える文である。
    失敗 {
        /// 状態遷移関数が状態遷移失敗結果に入れて返した状態。状態遷移の受け取った状態と等しくなければならず、探索がそれを確かめる。
        元の状態: 状態,
        /// 何が成立しなかったかを人へ伝える文。
        説明: String,
    },
}

impl<値> 数え上げ<値> {
    /// 実際に試す値の並び。全件でも標本でも、試す並びはこの1つのメソッドから取る。
    pub fn 試す値一覧(&self) -> &[値] {
        match self {
            Self::全件(一覧) => 一覧,
            Self::連続量を含む標本 { 標本, .. } => 標本,
        }
    }

    /// 連続量を含むならその説明。全件なら値なしである。
    pub fn 連続量の説明(&self) -> Option<&str> {
        match self {
            Self::全件(_) => None,
            Self::連続量を含む標本 { 連続量の説明, .. } => Some(連続量の説明),
        }
    }
}
