//! 設計概念の識別子の同一性を固定する試験。
//!
//! 名前空間と所有者の並びは、どちらも同一性の欄である。片方を落として同一性を決めると、
//! 実行時のドメイン概念と定義をたどれなかったRustの型が同じ識別子になり、
//! `旅行者::更新する` と `世界::更新する` も同じ識別子になる。その2つが起きないことをここで固定する。

use crate::設計概念の識別子;

#[test]
fn 名前空間が違えばモジュールパスと名前が同じでも別の識別子である() {
    let 項目 = 設計概念の識別子::Rustの項目として生成する("blitz_esca::traveler", "旅行者");
    let ドメイン概念 = 設計概念の識別子::実行時のドメイン概念として生成する("blitz_esca::traveler", "旅行者");
    assert_ne!(項目, ドメイン概念, "名前空間の違いが同一性へ効いていない");
}

#[test]
fn 所有者の並びが違えば別の識別子である() {
    let 旅行者の更新 = 設計概念の識別子::Rustの項目として生成する("blitz_esca::traveler", "更新する").所有者を添える(vec!["旅行者".to_string()]);
    let 世界の更新 = 設計概念の識別子::Rustの項目として生成する("blitz_esca::traveler", "更新する").所有者を添える(vec!["世界".to_string()]);
    assert_ne!(旅行者の更新, 世界の更新, "所有者の並びの違いが同一性へ効いていない");
    assert_ne!(旅行者の更新, 設計概念の識別子::Rustの項目として生成する("blitz_esca::traveler", "更新する"), "所有者の有無が同一性へ効いていない");
}

#[test]
fn 所有者を添えた識別子の表記がモジュールパスと所有者と名前を繋いだ形である() {
    let 識別子 = 設計概念の識別子::Rustの項目として生成する("blitz_esca::traveler", "更新する").所有者を添える(vec!["旅行者".to_string()]);
    assert_eq!(識別子.表記(), "blitz_esca::traveler::旅行者::更新する");
}

#[test]
fn 実行時のドメイン概念はモジュールパスが空でも定義をたどれていない扱いにしない() {
    let ドメイン概念 = 設計概念の識別子::実行時のドメイン概念として生成する("", "旅行者の現在地(東1マス, 北0マス)");
    assert!(!ドメイン概念.Rustの項目でありながら定義をたどれていないか(), "実行時のドメイン概念を未解決のRustの型と読み違えている");
    let たどれなかった型 = 設計概念の識別子::Rustの項目として生成する("", "たどれなかった型");
    assert!(たどれなかった型.Rustの項目でありながら定義をたどれていないか(), "定義をたどれなかったRustの型を未解決と判定できていない");
}
