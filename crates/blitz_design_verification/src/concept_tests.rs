//! 設計概念の識別子の同一性と、名前空間と種類が揃うことを固定する試験。
//!
//! 名前空間と所有者の並びは、どちらも同一性の欄である。片方を落として同一性を決めると、
//! 実行時のドメイン概念と定義をたどれなかったRustの型が同じ識別子になり、
//! `旅行者::更新する` と `世界::更新する` も同じ識別子になる。その2つが起きないことをここで固定する。
//!
//! あわせて、実行時のドメイン概念を節点として設計関係グラフへ置けることと、その節点の名前空間と種類が必ず揃うことを固定する。
//! `ゲーム世界の個体` は `struct` ではないため、偽の型の節点を作らずに `識別する` の目的語へ置けることがIssue #158の代表ケースである。
//!
//! あわせて、同じ識別子で種類の違う2つの参照が値として等しくないことを固定する。グラフへの問いはこの等価で照合するため、
//! ここが等しくなると `トレイト Foo` へ張った辺を `型 Foo` の問いが借りる。同一性が一致することは同時に固定する。
//! その一致が残っているからこそ、種類の食い違いが同一性の衝突として数えられる。

use std::path::PathBuf;

use crate::{抽出の出どころ, 抽出元の構文, 設計概念, 設計概念の名前空間, 設計概念の種類, 設計概念の識別子, 設計概念への参照, 設計関係, 設計関係の種類, 設計関係グラフ};

#[test]
fn 名前空間が違えばモジュールパスと名前が同じでも別の識別子である() {
    let 項目 = 設計概念の識別子::Rustの項目として生成する("blitz_esca::traveler", "旅行者");
    let ドメイン概念 = 設計概念の識別子::実行時のドメイン概念として生成する("blitz_esca::traveler", "旅行者");
    assert_ne!(項目, ドメイン概念, "名前空間の違いが同一性へ効いていない");
}

#[test]
fn 所有者の並びが違えば別の識別子である() {
    let 旅行者の更新 = 設計概念の識別子::Rustの項目として生成する("blitz_esca::traveler", "更新する").所有者を添える(vec!["旅行者".to_string()]);
    let 世界の更新 = 設計概念の識別子::Rustの項目として生成する("blitz_esca::traveler", "更新する").所有者を添える(vec!["世界".to_string()]);
    assert_ne!(旅行者の更新, 世界の更新, "所有者の並びの違いが同一性へ効いていない");
    assert_ne!(旅行者の更新, 設計概念の識別子::Rustの項目として生成する("blitz_esca::traveler", "更新する"), "所有者の有無が同一性へ効いていない");
}

#[test]
fn 所有者を添えた識別子の表記がモジュールパスと所有者と名前を繋いだ形である() {
    let 識別子 = 設計概念の識別子::Rustの項目として生成する("blitz_esca::traveler", "更新する").所有者を添える(vec!["旅行者".to_string()]);
    assert_eq!(識別子.表記(), "blitz_esca::traveler::旅行者::更新する");
}

#[test]
fn 実行時のドメイン概念はモジュールパスが空でも定義をたどれていない扱いにしない() {
    let ドメイン概念 = 設計概念の識別子::実行時のドメイン概念として生成する("", "旅行者の現在地(東1マス, 北0マス)");
    assert!(!ドメイン概念.Rustの項目でありながら定義をたどれていないか(), "実行時のドメイン概念を未解決のRustの型と読み違えている");
    let たどれなかった型 = 設計概念の識別子::Rustの項目として生成する("", "たどれなかった型");
    assert!(たどれなかった型.Rustの項目でありながら定義をたどれていないか(), "定義をたどれなかったRustの型を未解決と判定できていない");
}

#[test]
fn 実行時のドメイン概念の節点は名前空間と種類の両方が実行時のドメイン概念である() {
    let 節点 = 設計概念::実行時のドメイン概念として生成する("ゲーム世界", "ゲーム世界の個体");
    assert_eq!(節点.種類(), 設計概念の種類::実行時のドメイン概念, "実行時のドメイン概念の節点の種類が揃っていない");
    assert_eq!(節点.識別子().名前空間, 設計概念の名前空間::実行時のドメイン概念, "実行時のドメイン概念の節点の名前空間が揃っていない");
    let 型の節点 = 設計概念::型として生成する("blitz_esca::traveler", "旅行者");
    assert_eq!(型の節点.識別子().名前空間, 設計概念の名前空間::Rustの項目, "Rustの項目の節点の名前空間が揃っていない");
    assert_eq!(型の節点.種類(), 設計概念の種類::型, "Rustの項目の節点の種類が揃っていない");
}

#[test]
fn 実行時個体の識別子が実行時のドメイン概念を識別する関係をグラフへ置ける() {
    let 識別子の型 = 設計概念::型として生成する("blitz_esca::world", "ゲーム世界の実行時個体ID");
    let 個体 = 設計概念::実行時のドメイン概念として生成する("ゲーム世界", "ゲーム世界の個体");
    let 辺 = 設計関係 {
        主語: 識別子の型.参照を組む(),
        種類: 設計関係の種類::識別する,
        目的語: 個体.参照を組む(),
        出どころ: 抽出の出どころ {
            パス: PathBuf::from("crates/blitz_esca/src/world.rs"),
            行番号: 1,
            構文: 抽出元の構文::エンティティの識別子の関連型,
        },
    };
    let 結末 = 設計関係グラフ::生成する(vec![識別子の型.clone(), 個体.clone()], vec![辺]);
    assert!(結末.同一性の衝突一覧.is_empty(), "名前空間の違う2つの節点が衝突として数えられた: {:?}", 結末.同一性の衝突一覧);
    assert!(
        結末.グラフ.関係が在るか(&識別子の型.参照を組む(), 設計関係の種類::識別する, &個体.参照を組む()),
        "実行時のドメイン概念を目的語にした識別するの辺がグラフに無い"
    );
}

#[test]
fn 同じ識別子で種類の違う2つの参照は値として等しくないが同一性は一致する() {
    let 型の参照 = 設計概念への参照::型として生成する("blitz_esca::traveler", "旅行者");
    let トレイトの参照 = 設計概念への参照::トレイトとして生成する("blitz_esca::traveler", "旅行者");
    assert_ne!(型の参照, トレイトの参照, "種類の違いが参照の等価へ効いていない");
    assert_eq!(型の参照.識別子(), トレイトの参照.識別子(), "種類が同一性へ混ざっており、同一性の衝突が原理的に起きなくなっている");
    assert_eq!(型の参照.種類(), 設計概念の種類::型);
    assert_eq!(トレイトの参照.種類(), 設計概念の種類::トレイト);
}
