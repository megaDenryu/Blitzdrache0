//! 抽出の欠落が、その欠落の弱める答えを問う原子だけを未決定へ倒し、別の答えを問う原子を倒さないことを固定する試験。
//!
//! 絞る前の検証器は、欠落が1件でも在れば不在を根拠にした答えを種類を問わず未決定にしていた。その形へ戻ると、
//! 関数の署名の型の表記を読めない欠けが、保持する関係や別の種類の設計関係の答えまで未決定へ倒し、存在理由の公理が答えを失う。

use crate::{プリミティブな関係の種類, 欠落が弱める答え, 落とした理由ごとの件数, 設計関係の種類, 関係を落とした抽出の欠落};

use super::super::super::evidence::{未決定の理由, 検証結果};
use super::super::super::proposition::命題;
use super::super::super::原子命題の定義::{原子命題, 項};
use super::super::{命題の検証器, 構造の検証器};
use super::{保持の原子, 型の参照, 小さなグラフ, 関係の原子};

/// 渡した答えだけを弱める件を1件持つ欠落。
fn 答えを弱める欠落(答え一覧: Vec<欠落が弱める答え>) -> 関係を落とした抽出の欠落 {
    関係を落とした抽出の欠落::生成する(
        vec![落とした理由ごとの件数 {
            理由の説明: "試験が置いた読めない表記".to_string(),
            件数: 1,
            弱める答え一覧: 答え一覧,
        }],
        &[],
    )
}

// 小さなグラフに無い識別するの関係。辺の不在から反証される。
fn 無い識別するの関係() -> 命題 {
    関係の原子(型の参照("旅行者"), 設計関係の種類::識別する, 型の参照("旅行者ID"))
}

// 小さなグラフに無い保持する関係。辺の不在から反証される。
fn 無い保持する関係() -> 命題 {
    保持の原子(型の参照("旅行者ID"), 型の参照("旅行者"))
}

fn 未決定か(結果: &検証結果) -> bool {
    matches!(結果, 検証結果::未決定(未決定の理由::関係を落とした抽出の欠落が在る(_)))
}

#[test]
fn 保持するの欠けだけのとき設計関係の答えは弱まらず保持するの答えだけが未決定になる() {
    let グラフ = 小さなグラフ();
    let 検証器 = 構造の検証器::生成する(&グラフ, 答えを弱める欠落(vec![欠落が弱める答え::プリミティブな関係(プリミティブな関係の種類::保持する)]));
    assert!(検証器.検証する(&無い識別するの関係()).反証済みか());
    assert!(未決定か(&検証器.検証する(&無い保持する関係())), "{}", 検証器.検証する(&無い保持する関係()).表記());
}

#[test]
fn 設計関係の欠けだけのとき保持するの答えは弱まらずその種類の設計関係の答えだけが未決定になる() {
    let グラフ = 小さなグラフ();
    let 検証器 = 構造の検証器::生成する(&グラフ, 答えを弱める欠落(vec![欠落が弱める答え::設計関係(設計関係の種類::識別する)]));
    assert!(検証器.検証する(&無い保持する関係()).反証済みか());
    assert!(未決定か(&検証器.検証する(&無い識別するの関係())));
    let 無い消費する = 関係の原子(型の参照("旅行者"), 設計関係の種類::消費する, 型の参照("旅行者ID"));
    assert!(検証器.検証する(&無い消費する).反証済みか(), "識別するの欠けが消費するの答えを弱めている");
}

#[test]
fn 保持すると設計関係の両方の欠けが在るとき両方の答えが未決定になる() {
    let グラフ = 小さなグラフ();
    let 検証器 = 構造の検証器::生成する(
        &グラフ,
        答えを弱める欠落(vec![欠落が弱める答え::プリミティブな関係(プリミティブな関係の種類::保持する), 欠落が弱める答え::設計関係(設計関係の種類::識別する)]),
    );
    assert!(未決定か(&検証器.検証する(&無い保持する関係())));
    assert!(未決定か(&検証器.検証する(&無い識別するの関係())));
}

#[test]
fn 設計関係へ1つも参加していないは設計関係の欠けのときだけ弱まる() {
    let グラフ = 小さなグラフ();
    let 参加していない = 命題::原子から組む(原子命題::設計関係へ1つも参加していない {
        概念: 項::名指した概念(型の参照("関係へ参加しない型")),
    });
    let 保持するの欠け = 構造の検証器::生成する(&グラフ, 答えを弱める欠落(vec![欠落が弱める答え::プリミティブな関係(プリミティブな関係の種類::保持する), 欠落が弱める答え::分類]));
    assert!(保持するの欠け.検証する(&参加していない).証明済みか(), "参加に数えない保持するか分類の欠けで参加の答えを弱めている");
    let 設計関係の欠け = 構造の検証器::生成する(&グラフ, 答えを弱める欠落(vec![欠落が弱める答え::設計関係(設計関係の種類::参照する)]));
    assert!(未決定か(&設計関係の欠け.検証する(&参加していない)));
}
