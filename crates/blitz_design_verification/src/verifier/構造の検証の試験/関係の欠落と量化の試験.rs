//! 関係の端点が欠けて主語が量化の対象集合から消えたとき、量化が見た範囲の証拠だけを答える試験。

use crate::{設計概念ノード, 設計解釈マーカーの宣言の一覧, 設計関係の抽出漏れ, 設計関係の結び付き方, 設計関係グラフ, 関数の引数と戻り値の役目};

use super::super::super::evidence::{未決定の理由, 検証結果};
