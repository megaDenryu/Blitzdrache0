//! グラフから列挙したマーカーを持つ設計概念と設計関係の主語の2つの対象集合が、その対象集合を導く答えを弱める欠落のときだけ全件と言えなくなることを固定する試験。
//!
//! どちらの対象集合も、本体が全件で成り立つ全称で確かめる。全件のままなら証明済みになり、全件と言えなければ未決定になる。
//! 別の答えを弱める欠落で全件と言えなくすると、関数の署名の読めない表記のような無関係な欠けが量化の答えを全て未決定へ倒す。

use std::path::PathBuf;

use crate::{
    プリミティブな関係の種類, マーカーの実装の事実, 事実の出どころ, 分類の事実, 欠落が弱める答え, 落とした理由ごとの件数, 設計概念, 設計関係の種類, 設計関係グラフ, 関係を落とした抽出の欠落
};

use super::super::super::atom::{原子命題, 項};
use super::super::super::evidence::検証結果;
use super::super::super::proposition::命題;
use super::super::super::quantification::{対象集合, 束縛変数};
use super::super::{命題の検証器, 構造の検証器};
use super::{トレイトの参照, 型の参照, 関係};

// 旅行者が `M状態` を実装し、旅行者IDが旅行者を識別するグラフ。
fn 分類と識別するを持つグラフ() -> 設計関係グラフ {
    let 概念一覧 = vec![
        設計概念::トレイトとして生成する("blitz_esca::traveler", "M状態"),
        設計概念::型として生成する("blitz_esca::traveler", "旅行者"),
        設計概念::型として生成する("blitz_esca::traveler", "旅行者ID"),
    ];
    let 実装 = マーカーの実装の事実 {
        型: 型の参照("旅行者"),
        マーカー: トレイトの参照("M状態"),
        出どころ: 事実の出どころ {
            パス: PathBuf::from("crates/blitz_esca/src/traveler.rs"),
            行番号: 1,
        },
    };
    let 分類 = 分類の事実::生成する(vec![トレイトの参照("M状態")], vec![実装], Vec::new());
    設計関係グラフ::生成する(概念一覧, vec![関係(型の参照("旅行者ID"), 設計関係の種類::識別する, 型の参照("旅行者"))], Vec::new(), 分類).グラフ
}

// 渡した答えだけを弱める件を1件持つ欠落。
fn 答えを弱める欠落(答え: 欠落が弱める答え) -> 関係を落とした抽出の欠落 {
    let 件 = 落とした理由ごとの件数 {
        理由の説明: "試験が置いた欠落".to_string(),
        件数: 1,
        弱める答え一覧: vec![答え],
    };
    関係を落とした抽出の欠落::生成する(vec![件], &[])
}

// `M状態` を分類に持つ概念は全て `M状態` を持つ、という全件で成り立つ全称。
fn マーカーを持つ概念の全称() -> 命題 {
    let 束縛 = 束縛変数::生成する("概念");
    let 本体 = 命題::原子から組む(原子命題::マーカーを持つ {
        概念: 項::束縛変数(束縛.clone()),
        マーカー名: "M状態".to_string(),
    });
    命題::全称を組む(束縛, 対象集合::マーカーを持つ設計概念 { マーカー名: "M状態".to_string() }, 本体)
}

// 識別するの主語は全て旅行者を識別する、という全件で成り立つ全称。
fn 識別するの主語の全称() -> 命題 {
    let 束縛 = 束縛変数::生成する("概念");
    let 本体 = 命題::原子から組む(原子命題::設計関係が在る {
        主語: 項::束縛変数(束縛.clone()),
        種類: 設計関係の種類::識別する,
        目的語: 項::名指した概念(型の参照("旅行者")),
    });
    命題::全称を組む(束縛, 対象集合::全ての設計関係の主語(設計関係の種類::識別する), 本体)
}

fn 欠落の下で検証する(命題: &命題, 答え: 欠落が弱める答え) -> 検証結果 {
    構造の検証器::生成する(&分類と識別するを持つグラフ(), 答えを弱める欠落(答え)).検証する(命題)
}

#[test]
fn マーカーを持つ設計概念は分類でない答えの欠落では全件のままである() {
    let 結果 = 欠落の下で検証する(&マーカーを持つ概念の全称(), 欠落が弱める答え::プリミティブな関係(プリミティブな関係の種類::保持する));
    assert!(結果.証明済みか(), "{}", 結果.表記());
}

#[test]
fn マーカーを持つ設計概念は分類の答えの欠落では全件と言えない() {
    let 結果 = 欠落の下で検証する(&マーカーを持つ概念の全称(), 欠落が弱める答え::分類);
    assert!(matches!(結果, 検証結果::未決定(_)), "{}", 結果.表記());
}

#[test]
fn 設計関係の主語は別の種類の答えの欠落では全件のままである() {
    let 結果 = 欠落の下で検証する(&識別するの主語の全称(), 欠落が弱める答え::設計関係(設計関係の種類::消費する));
    assert!(結果.証明済みか(), "{}", 結果.表記());
}

#[test]
fn 設計関係の主語は同じ種類の答えの欠落では全件と言えない() {
    let 結果 = 欠落の下で検証する(&識別するの主語の全称(), 欠落が弱める答え::設計関係(設計関係の種類::識別する));
    assert!(matches!(結果, 検証結果::未決定(_)), "{}", 結果.表記());
}
