//! 直接のエッジを問う原子と、エッジを辿る経路を問う原子が別の答えを返すことを固定する試験。
//!
//! `旅行者` が `現在地` を保持し `現在地` が `東西の位置` を保持すれば、`旅行者` は `東西の位置` を間接に保持する。
//! **ソースはその直接のエッジを宣言しない。** したがって間接の保持を直接のエッジで問うと、正しい設計が偽の反証を受ける。
//! 同じ主語と目的語について2つの原子が違う答えを返すことが、この区別が働いている証拠である。

#![allow(clippy::unwrap_used)]

use crate::設計関係の抽出漏れ;

use super::super::super::evidence::検証結果;

use super::super::{命題の検証器, 構造の検証器};
use super::{保持が二段のグラフ, 保持の原子, 保持の経路の原子, 型の参照};

#[test]
fn 二段の保持は経路の原子で証明済みになる() {
    let グラフ = 保持が二段のグラフ();
    let 経路 = 保持の経路の原子(型の参照("旅行者"), 型の参照("東西の位置"));
    let 結果 = 構造の検証器::生成する(&グラフ, 設計関係の抽出漏れ::無い()).検証する(&経路);
    assert!(結果.証明済みか(), "2本のエッジで繋がっているのに経路の原子が証明済みにならなかった: {}", 結果.表記());
}

#[test]
fn 同じ主語と目的語でも直接のエッジの原子は反証済みになる() {
    let グラフ = 保持が二段のグラフ();
    let 直接のエッジ = 保持の原子(型の参照("旅行者"), 型の参照("東西の位置"));
    let 結果 = 構造の検証器::生成する(&グラフ, 設計関係の抽出漏れ::無い()).検証する(&直接のエッジ);
    assert!(結果.反証済みか(), "直接のエッジを宣言していないのに直接のエッジの原子が反証済みにならなかった: {}", 結果.表記());
}

#[test]
fn 経路が無い向きでは経路の原子が反証済みになる() {
    let グラフ = 保持が二段のグラフ();
    let 逆向きの経路 = 保持の経路の原子(型の参照("東西の位置"), 型の参照("旅行者"));
    let 結果 = 構造の検証器::生成する(&グラフ, 設計関係の抽出漏れ::無い()).検証する(&逆向きの経路);
    assert!(結果.反証済みか(), "エッジが逆向きにしか無いのに経路の原子が反証済みにならなかった: {}", 結果.表記());
}

#[test]
fn 経路で示した証拠の説明は経路で答えたことを言う() {
    let グラフ = 保持が二段のグラフ();
    let 経路 = 保持の経路の原子(型の参照("旅行者"), 型の参照("東西の位置"));
    let 検証結果::証明済み(証拠) = 構造の検証器::生成する(&グラフ, 設計関係の抽出漏れ::無い()).検証する(&経路) else {
        panic!("2本のエッジで繋がっているのに証明済みにならなかった");
    };
    assert!(証拠.説明().contains("経路"), "経路で示した証拠が直接のエッジのように読める説明になっている: {}", 証拠.説明());
}
