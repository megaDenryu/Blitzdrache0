//! マーカーを持つ設計概念の量化の対象集合と `マーカー保有命題` の原子が、エッジでなく、型に付いているマーカー(上位トレイトの宣言で閉じたもの)を読むことを固定する試験。
//!
//! 固定するのは3つである。上位トレイトの宣言(`trait M不変エンティティ: Mエンティティ`)があってもトレイトは母集団へ入らないこと。
//! `M状態` を実装した型は、`M不変データ` を直に実装していなくても上位トレイトの宣言により `M不変データ` も付いていること。
//! マーカーだけが付いていてエッジを持たない型は、設計関係へ参加していないと答えられること。

#![allow(clippy::unwrap_used)]

use std::path::PathBuf;

use crate::{マーカーの実装, 上位トレイトの宣言, 宣言の出どころ, 設計概念の識別用情報, 設計概念ノード, 設計解釈マーカーの宣言の一覧, 設計関係グラフ, 関係を落とした抽出の欠落};

use super::super::super::evidence::{未決定の理由, 検証結果};
use super::super::super::proposition::命題;
use super::super::super::原子命題の定義::{原子命題, 項};
use super::super::super::量化の語彙::{束縛変数, 量化の対象集合};
use super::super::{命題の検証器, 構造の検証器};
use crate::{マーカー保有命題, 孤立命題};

const 正本のモジュールパス: &str = "blitz_design::marker";

fn 型の参照(名前: &str) -> 設計概念の識別用情報 {
    設計概念の識別用情報::型として生成する("blitz_esca::traveler", 名前)
}

fn トレイトの参照(名前: &str) -> 設計概念の識別用情報 {
    設計概念の識別用情報::トレイトとして生成する(正本のモジュールパス, 名前)
}

fn 出どころ() -> 宣言の出どころ {
    宣言の出どころ::生成する(PathBuf::from("crates/blitz_design/src/marker.rs"), 1)
}

/// `trait M不変エンティティ: Mエンティティ` と `trait M状態: M不変データ` を持ち、`旅行者の現在地` が `M状態` だけを実装するグラフ。
/// `Mエンティティ` を実装した型は1件も無い。エッジは1本も無い。
fn マーカーだけが付いているグラフ() -> 設計関係グラフ {
    let トレイト一覧 = ["Mエンティティ", "M不変エンティティ", "M状態", "M不変データ"].map(|名前| 設計概念ノード::トレイトとして生成する(正本のモジュールパス, 名前));
    let mut 概念一覧 = トレイト一覧.to_vec();
    概念一覧.push(設計概念ノード::型として生成する("blitz_esca::traveler", "旅行者の現在地"));
    let 上位 = |トレイト: &str, 上位トレイト: &str| 上位トレイトの宣言::生成する(トレイトの参照(トレイト), トレイトの参照(上位トレイト), 出どころ());
    let 実装 = マーカーの実装::生成する(型の参照("旅行者の現在地"), トレイトの参照("M状態"), 出どころ());
    let 設計解釈マーカーの宣言の一覧 = 設計解釈マーカーの宣言の一覧::生成する(
        ["Mエンティティ", "M不変エンティティ", "M状態", "M不変データ"].map(トレイトの参照).to_vec(),
        vec![実装],
        vec![上位("M不変エンティティ", "Mエンティティ"), 上位("M状態", "M不変データ")],
    );
    設計関係グラフ::生成する(概念一覧, Vec::new(), Vec::new(), 設計解釈マーカーの宣言の一覧).グラフを取り出す()
}

fn マーカーを持つ型についての全称(マーカー名: &str, 本体: impl Fn(項) -> 命題) -> 命題 {
    let 束縛 = 束縛変数::生成する("概念");
    命題::全称を組む(束縛.clone(), 量化の対象集合::マーカーを持つ設計概念 { マーカー名: マーカー名.to_string() }, 本体(項::束縛変数(束縛)))
}

fn マーカー保有命題を組む(概念: 項, マーカー名: &str) -> 命題 {
    命題::原子から組む(原子命題::マーカー保有命題(マーカー保有命題::生成する(概念, マーカー名)))
}

#[test]
fn マーカーを実装した型が0件なら上位トレイトの宣言が在っても全称は未決定になる() {
    let グラフ = マーカーだけが付いているグラフ();
    let 全称 = マーカーを持つ型についての全称("Mエンティティ", |概念| マーカー保有命題を組む(概念, "Mエンティティ"));
    let 結果 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&全称);
    assert!(
        matches!(結果, 検証結果::未決定(未決定の理由::量化の対象集合が空である(_))),
        "Mエンティティを実装した型が0件なのに未決定にならなかった(上位トレイトの宣言のトレイトを母集団へ入れている): {}",
        結果.表記()
    );
}

#[test]
fn 直に実装していないマーカーも上位トレイトの宣言により付いている() {
    let グラフ = マーカーだけが付いているグラフ();
    let 全称 = マーカーを持つ型についての全称("M不変データ", |概念| マーカー保有命題を組む(概念, "M状態"));
    let 結果 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&全称);
    assert!(結果.証明済みか(), "M状態を実装した型がM不変データを持つ母集団へ入っていない: {}", 結果.表記());
    let 直の問い = マーカー保有命題を組む(項::名指した概念(型の参照("旅行者の現在地")), "M不変データ");
    assert!(構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&直の問い).証明済みか());
}

#[test]
fn マーカーだけが付いている型は設計関係へ参加していないと答える() {
    let グラフ = マーカーだけが付いているグラフ();
    let 参加していない = 命題::原子から組む(原子命題::孤立命題(孤立命題::生成する(項::名指した概念(型の参照("旅行者の現在地")))));
    assert!(
        構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&参加していない).証明済みか(),
        "付いているマーカーをエッジとして参加に数えている"
    );
}

#[test]
fn 持っていないマーカーは欠落が在れば未決定になる() {
    let グラフ = マーカーだけが付いているグラフ();
    let 問い = マーカー保有命題を組む(項::名指した概念(型の参照("旅行者の現在地")), "Mエンティティ");
    assert!(構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&問い).反証済みか());
    let 欠落 = 関係を落とした抽出の欠落::生成する(
        vec![crate::落とした理由ごとの件数::生成する(
            "上位トレイトの宣言を読めない".to_string(),
            1,
            vec![crate::欠落が弱める答え::付いているマーカー],
        )],
        &[],
    );
    let 結果 = 構造の検証器::生成する(&グラフ, 欠落).検証する(&問い);
    assert!(matches!(結果, 検証結果::未決定(未決定の理由::関係を落とした抽出の欠落が在る(_))), "宣言を落としたのにラベルの不在で反証した: {}", 結果.表記());
}
