//! 3値の論理結合の規則を固定する試験。**未決定が黙って偽へ潰れないこと**をこの試験が守る。

#![allow(clippy::unwrap_used)]

use super::super::evidence::{反例, 未決定の理由, 検証の方式, 検証結果, 証拠};
use super::three_valued::子の命題の検証結果一覧;

fn 証明済み() -> 検証結果 {
    検証結果::証明済み(証拠 {
        方式: 検証の方式::設計関係グラフ,
        見た対象の件数: 1,
        説明: "見た".to_string(),
    })
}

fn 反証済み() -> 検証結果 {
    検証結果::反証済み(反例 {
        方式: 検証の方式::設計関係グラフ,
        説明: "破れた".to_string(),
        再現の材料: Vec::new(),
    })
}

fn 未決定() -> 検証結果 {
    検証結果::未決定(未決定の理由::この検証器が扱わない式を含む("扱わない".to_string()))
}

fn 連言(検証結果一覧: Vec<検証結果>) -> 検証結果 {
    子の命題の検証結果一覧::生成する(検証の方式::設計関係グラフ, 検証結果一覧).連言として判定する()
}

fn 選言(検証結果一覧: Vec<検証結果>) -> 検証結果 {
    子の命題の検証結果一覧::生成する(検証の方式::設計関係グラフ, 検証結果一覧).選言として判定する()
}

#[test]
fn 連言は未決定が混じれば未決定であり偽へ潰れない() {
    assert!(matches!(連言(vec![証明済み(), 未決定()]), 検証結果::未決定(_)));
    assert!(matches!(連言(vec![証明済み(), 証明済み()]), 検証結果::証明済み(_)));
    assert!(matches!(連言(vec![未決定(), 反証済み()]), 検証結果::反証済み(_)));
}

#[test]
fn 選言は未決定が混じれば未決定であり偽へ潰れない() {
    assert!(matches!(選言(vec![反証済み(), 未決定()]), 検証結果::未決定(_)));
    assert!(matches!(選言(vec![反証済み(), 証明済み()]), 検証結果::証明済み(_)));
    assert!(matches!(選言(vec![反証済み(), 反証済み()]), 検証結果::反証済み(_)));
}

#[test]
fn 選言が全件で反証されたときの反例は材料を持たず説明が項の数と各項の破れを持つ() {
    let 検証結果::反証済み(反例) = 選言(vec![反証済み(), 反証済み()]) else {
        panic!("項が全て反証済みなら選言は反証済みでなければならない");
    };
    // 指し示す1件が無いため材料は空でよいが、そのぶん説明が項の数と各項の破れを持たなければ未決定と区別できない。
    assert!(反例.再現の材料.is_empty(), "選言の反例は指し示す1件を持たないのに材料が入っている: {:?}", 反例.再現の材料);
    assert!(反例.説明.contains("2件"), "説明が項の数を持たない: {}", 反例.説明);
    assert!(反例.説明.contains("破れた"), "説明が各項の破れを持たない: {}", 反例.説明);
}

#[test]
fn 否定は証明済みと反証済みを入れ替え未決定は未決定のままである() {
    assert!(matches!(証明済み().否定へ反転する(), 検証結果::反証済み(_)));
    assert!(matches!(反証済み().否定へ反転する(), 検証結果::証明済み(_)));
    assert!(matches!(未決定().否定へ反転する(), 検証結果::未決定(_)));
}

#[test]
fn 含意は前件が反証済みなら空虚に成立し前件が未決定なら未決定である() {
    assert!(matches!(反証済み().前件だけで含意が決まる結果を求める(), Some(検証結果::証明済み(_))));
    assert!(matches!(未決定().前件だけで含意が決まる結果を求める(), Some(検証結果::未決定(_))));
    assert!(証明済み().前件だけで含意が決まる結果を求める().is_none());
}
