//! 項とマーカー名から、グラフに実在する節点への参照を求める工程。
//!
//! **偽の反証を出さないための3つの未決定をこの1箇所が持つ。** 束縛変数へ割り当てが無い・型の定義をたどれず
//! モジュールパスが未解決である・その概念がグラフに無い、のどれかなら未決定の理由を返す。
//! 未解決のモジュールパスを普通の節点として扱うと、抽出器がたどれなかった型についての命題が全部反証される。

use crate::{設計概念の種類, 設計概念への参照};

use super::super::super::super::atom::項;
use super::super::super::super::evidence::未決定の理由;
use super::super::super::super::quantification::束縛の割り当て;
use super::super::構造の検証器;

impl 構造の検証器<'_> {
    pub(super) fn 項からグラフの節点を求める(&self, 項: &項, 割り当て: &束縛の割り当て) -> Result<設計概念への参照, 未決定の理由> {
        let Some(参照) = 項.束縛の割り当てから設計概念への参照を求める(割り当て) else {
            return Err(未決定の理由::この検証器が扱わない式を含む(format!("束縛変数{}へ当たる概念が割り当てに無い", 項.表記())));
        };
        if 参照.識別子().Rustの項目でありながら定義をたどれていないか() {
            return Err(未決定の理由::型の定義のモジュールパスが未解決である(
                format!("{}の定義をたどれておらずモジュールパスが空である", 参照.識別子().名前),
            ));
        }
        // 節点の実在は同一性だけで見る。種類まで見ると、項が名乗る種類と節点の種類が食い違うだけで在る概念を無いと答えることになる。
        if !self.グラフを貸す().概念一覧().iter().any(|概念| 概念.識別子() == 参照.識別子()) {
            return Err(未決定の理由::対象の概念がグラフに無い(参照.表記()));
        }
        Ok(参照)
    }

    /// マーカー名からトレイトの節点への参照を求める。名前だけで指すのは、命題の側がマーカーを名前で名指すためである。
    /// 同じ名前のトレイトが2つ以上在るときは一意に決まらないため未決定で答える(黙って先頭を選ばない)。
    pub(super) fn マーカー名からトレイトの節点を求める(&self, マーカー名: &str) -> Result<設計概念への参照, 未決定の理由> {
        let 候補: Vec<設計概念への参照> = self
            .グラフを貸す()
            .種類で絞った概念一覧(設計概念の種類::トレイト)
            .into_iter()
            .filter(|概念| 概念.識別子().名前 == マーカー名)
            .map(|概念| 概念.参照を組む())
            .collect();
        match 候補.as_slice() {
            [候補1件] => Ok(候補1件.clone()),
            [] => Err(未決定の理由::対象の概念がグラフに無い(format!("{マーカー名}という名前のトレイトの節点がグラフに無い"))),
            _ => Err(未決定の理由::この検証器が扱わない式を含む(
                format!("{マーカー名}という名前のトレイトの節点が{}件在り一意に決まらない", 候補.len()),
            )),
        }
    }
}
