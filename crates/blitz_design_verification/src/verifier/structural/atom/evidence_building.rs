//! 構造の原子命題の答えに添える証拠と反例を組む工程。
//!
//! 3つの原子命題が同じ形の証拠と反例を返すことをこの1箇所が守る。呼び出し側で綴ると、原子命題を1つ足したときに
//! そこだけ方式も再現の材料も無い答えになる。
//!
//! 検証器のメソッドでなく自由関数で置くのは、組み立てが検証器の借りているグラフを1度も読まない純粋な計算であり、
//! 状態を持たない処理を型のメソッドにすると、その型が何を触るのかが署名から読めなくなるためである。
//! 参照: グローバルCLAUDE.md「Rustの書き方の選択」条5(a)。

use crate::設計概念の識別子;

use super::super::super::super::evidence::{反例, 検証の方式, 検証結果, 証拠};

/// グラフがその問いへ肯定で答えたときの証拠。見た対象の件数は照合した関係の1件である。
pub(super) fn 設計関係を1件見た証拠(表記: &str) -> 検証結果 {
    検証結果::証明済み(証拠 {
        方式: 検証の方式::設計関係グラフ,
        見た対象の件数: 1,
        説明: format!("グラフが{表記}を答えた"),
    })
}

/// グラフがその問いへ否定で答えたときの反例。人が戻れるよう主語と目的語の表記を再現の材料へ残す。
pub(super) fn 設計関係が無い反例(表記: &str, 主語: &設計概念の識別子, 目的語: &設計概念の識別子) -> 検証結果 {
    検証結果::反証済み(反例 {
        方式: 検証の方式::設計関係グラフ,
        説明: format!("グラフが{表記}を答えなかった"),
        再現の材料: vec![("主語".to_string(), 主語.表記()), ("目的語".to_string(), 目的語.表記())],
    })
}
