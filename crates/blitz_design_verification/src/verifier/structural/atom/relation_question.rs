//! 関係の在り方の問い方。受け取るのは主語と種類と目的語、返すのはグラフの答えと、証拠と反例へ入れる表記である。
//!
//! **直接の辺と辿る経路は別の問いである。** 直接の辺はそのソースがその関係を宣言しているかを問い、
//! 辿る経路は宣言の連なりで推移的に成り立つかを問う。上位トレイトの関係は推移的であり、Rustは
//! `M時間局所状態: M不変データ` のような直接の辺を宣言しないため、後者でしか成り立たない。
//! 2つを1つの型の選択肢として持つのは、問いの違いが「グラフへ何を尋ねるか」と「説明にどう書くか」の
//! 2箇所へ同時に効き、片方だけを直すと経路で示した証拠が直接の辺のように読める文になるためである。

use crate::{設計概念の識別子, 設計関係の種類, 設計関係グラフ};

/// 関係が在ることをどう問うかの区別。
pub(super) enum 関係の問い方 {
    直接の辺,
    その種類の辺を辿る経路,
}

impl 関係の問い方 {
    /// その問い方でグラフへ問うた答え。
    pub(super) fn グラフへ問う(&self, グラフ: &設計関係グラフ, 主語: &設計概念の識別子, 種類: 設計関係の種類, 目的語: &設計概念の識別子) -> bool {
        match self {
            Self::直接の辺 => グラフ.関係が在るか(主語, 種類, 目的語),
            Self::その種類の辺を辿る経路 => グラフ.経路が在るか(主語, &[種類], 目的語),
        }
    }

    /// 証拠と反例の説明へ入れる、何を問うたかの表記。経路で示した答えが直接の辺と読み違えられないように語を分ける。
    pub(super) fn 表記(&self, 主語: &設計概念の識別子, 種類: 設計関係の種類, 目的語: &設計概念の識別子) -> String {
        match self {
            Self::直接の辺 => format!("{} {} {}", 主語.表記(), 種類.語(), 目的語.表記()),
            Self::その種類の辺を辿る経路 => format!("{}から{}の辺を辿って{}へ達する経路", 主語.表記(), 種類.語(), 目的語.表記()),
        }
    }
}
