//! 関係の在り方の問い方と、問う辺の高さ。受け取るのは主語と問う辺と目的語、返すのはグラフの答えと、証拠と反例へ入れる表記である。
//!
//! **直接の辺と辿る経路は別の問いである。** 直接の辺はそのソースがその関係を宣言しているかを問い、
//! 辿る経路は宣言の連なりで推移的に成り立つかを問う。間接の保持(`旅行者` が `現在地` を持ち、`現在地` が `東西の位置` を持つ)は
//! `旅行者 保持する 東西の位置` という直接の辺を持たないため、後者でしか成り立たない。
//! 2つを1つの型の選択肢として持つのは、問いの違いが「グラフへ何を尋ねるか」と「説明にどう書くか」の
//! 2箇所へ同時に効き、片方だけを直すと経路で示した証拠が直接の辺のように読める文になるためである。
//! **問う辺は、設計関係(設計の高さ)と保持する関係(プリミティブの高さ)のどちらかである。** 2つの高さを1つの問いへ混ぜないため、
//! グラフへは高さごとの別の問いで尋ねる(Issue #193)。

use crate::{設計概念への参照, 設計関係の種類, 設計関係グラフ};

/// 関係が在ることをどう問うかの区別。
pub(super) enum 関係の問い方 {
    直接の辺,
    その種類の辺を辿る経路,
}

/// どの高さのどの辺を問うかの区別。
#[derive(Clone, Copy)]
pub(super) enum 問う辺 {
    設計関係(設計関係の種類),
    保持する,
}

impl 問う辺 {
    // 表記に使う関係の語。
    const fn 語(self) -> &'static str {
        match self {
            Self::設計関係(種類) => 種類.語(),
            Self::保持する => "保持する",
        }
    }
}

impl 関係の問い方 {
    /// その問い方でグラフへ問うた答え。
    pub(super) fn グラフへ問う(&self, グラフ: &設計関係グラフ, 主語: &設計概念への参照, 辺: 問う辺, 目的語: &設計概念への参照) -> bool {
        match (self, 辺) {
            (Self::直接の辺, 問う辺::設計関係(種類)) => グラフ.関係が在るか(主語, 種類, 目的語),
            (Self::その種類の辺を辿る経路, 問う辺::設計関係(種類)) => グラフ.経路が在るか(主語, &[種類], 目的語),
            (Self::直接の辺, 問う辺::保持する) => グラフ.保持する関係が在るか(主語, 目的語),
            (Self::その種類の辺を辿る経路, 問う辺::保持する) => グラフ.保持する経路が在るか(主語, 目的語),
        }
    }

    /// 証拠と反例の説明へ入れる、何を問うたかの表記。経路で示した答えが直接の辺と読み違えられないように語を分ける。
    pub(super) fn 表記(&self, 主語: &設計概念への参照, 辺: 問う辺, 目的語: &設計概念への参照) -> String {
        match self {
            Self::直接の辺 => format!("{} {} {}", 主語.表記(), 辺.語(), 目的語.表記()),
            Self::その種類の辺を辿る経路 => format!("{}から{}の辺を辿って{}へ達する経路", 主語.表記(), 辺.語(), 目的語.表記()),
        }
    }
}
