//! 構造の原子命題をグラフへ問う工程。触れるのは借りているグラフだけであり、結合の規則を1つも持たない。
//!
//! 振る舞いの原子命題(発生する・遷移する・到達可能である)をこの検証器は解かず未決定で答える。解くのは
//! `crate::有限全数の検証器`である。偽で答えないのは、解けないことと成立しないことが別だからである。

mod evidence_building;
mod node_lookup;

use crate::設計関係の種類;

use super::super::super::atom::{原子命題, 項};
use super::super::super::evidence::{未決定の理由, 検証結果};
use super::super::super::quantification::束縛の割り当て;
use super::構造の検証器;

impl 構造の検証器<'_> {
    pub(super) fn 原子命題をグラフへ問う(&self, 原子: &原子命題, 割り当て: &束縛の割り当て) -> 検証結果 {
        match 原子 {
            原子命題::設計関係が在る { 主語, 種類, 目的語 } => self.関係の有無を問う(主語, *種類, 目的語, 割り当て),
            原子命題::マーカーを持つ { 概念, マーカー名 } => self.マーカーの有無を問う(概念, マーカー名, 割り当て),
            原子命題::設計関係へ1つも参加していない { 概念 } => self.参加の有無を問う(概念, 割り当て),
            原子命題::発生する { .. } | 原子命題::遷移する { .. } | 原子命題::到達可能である { .. } => {
                検証結果::未決定(未決定の理由::この検証器が扱わない式を含む(format!("構造の検証器は振る舞いの原子命題を解かない: {}", 原子.表記())))
            }
        }
    }

    fn 関係の有無を問う(&self, 主語: &項, 種類: 設計関係の種類, 目的語: &項, 割り当て: &束縛の割り当て) -> 検証結果 {
        let 主語の識別子 = match self.項からグラフの節点を求める(主語, 割り当て) {
            Ok(識別子) => 識別子,
            Err(理由) => return 検証結果::未決定(理由),
        };
        let 目的語の識別子 = match self.項からグラフの節点を求める(目的語, 割り当て) {
            Ok(識別子) => 識別子,
            Err(理由) => return 検証結果::未決定(理由),
        };
        let 表記 = format!("{} {} {}", 主語の識別子.表記(), 種類.語(), 目的語の識別子.表記());
        if self.グラフを貸す().関係が在るか(&主語の識別子, 種類, &目的語の識別子) {
            self.関係を1件見た証拠(&表記)
        } else {
            self.関係が無い反例(&表記, &主語の識別子, &目的語の識別子)
        }
    }

    fn マーカーの有無を問う(&self, 概念: &項, マーカー名: &str, 割り当て: &束縛の割り当て) -> 検証結果 {
        let 識別子 = match self.項からグラフの節点を求める(概念, 割り当て) {
            Ok(識別子) => 識別子,
            Err(理由) => return 検証結果::未決定(理由),
        };
        let マーカーの識別子 = match self.マーカー名からトレイトの節点を求める(マーカー名) {
            Ok(識別子) => 識別子,
            Err(理由) => return 検証結果::未決定(理由),
        };
        let 表記 = format!("{}は{マーカー名}を持つ", 識別子.表記());
        if self.グラフを貸す().関係が在るか(&識別子, 設計関係の種類::下位型である, &マーカーの識別子) {
            self.関係を1件見た証拠(&表記)
        } else {
            self.関係が無い反例(&表記, &識別子, &マーカーの識別子)
        }
    }

    fn 参加の有無を問う(&self, 概念: &項, 割り当て: &束縛の割り当て) -> 検証結果 {
        let 識別子 = match self.項からグラフの節点を求める(概念, 割り当て) {
            Ok(識別子) => 識別子,
            Err(理由) => return 検証結果::未決定(理由),
        };
        let 表記 = format!("{}は設計関係へ1つも参加していない", 識別子.表記());
        if self.グラフを貸す().関係へ1つも参加していないか(&識別子) {
            self.関係を1件見た証拠(&表記)
        } else {
            self.関係が無い反例(&表記, &識別子, &識別子)
        }
    }
}
