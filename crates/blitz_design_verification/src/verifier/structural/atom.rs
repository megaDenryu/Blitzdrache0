//! 構造の原子命題をグラフへ問う工程。触れるのは借りているグラフだけであり、結合の規則を1つも持たない。
//!
//! 振る舞いの原子命題(発生する・遷移する・到達可能である)をこの検証器は解かず未決定で答える。解くのは
//! `crate::有限全数の検証器`である。偽で答えないのは、解けないことと成立しないことが別だからである。
//!
//! **辺が見つからなかったことだけを根拠にした結果は、抽出が関係を落としているときに未決定へ落とす。**
//! 弱める規則の正本は `不在に由来する結果を弱める` の1つだけであり、3つの原子命題がそこを通る。

mod evidence_building;
mod node_lookup;
mod relation_question;

use evidence_building::{設計関係が無い反例, 設計関係を1件見た証拠};
use relation_question::{問う辺, 関係の問い方};

use crate::設計概念の種類;

use super::super::super::atom::{原子命題, 項};
use super::super::super::evidence::{未決定の理由, 検証結果};
use super::super::super::quantification::束縛の割り当て;
use super::構造の検証器;

impl 構造の検証器<'_> {
    pub(super) fn 原子命題をグラフへ問う(&self, 原子: &原子命題, 割り当て: &束縛の割り当て) -> 検証結果 {
        match 原子 {
            原子命題::設計関係が在る { 主語, 種類, 目的語 } => self.関係の有無を問う(主語, 問う辺::設計関係(*種類), 目的語, 割り当て, &関係の問い方::直接の辺),
            原子命題::設計関係の経路が在る { 主語, 種類, 目的語 } => self.関係の有無を問う(主語, 問う辺::設計関係(*種類), 目的語, 割り当て, &関係の問い方::その種類の辺を辿る経路),
            原子命題::保持する関係が在る { 主語, 目的語 } => self.関係の有無を問う(主語, 問う辺::保持する, 目的語, 割り当て, &関係の問い方::直接の辺),
            原子命題::保持する関係の経路が在る { 主語, 目的語 } => self.関係の有無を問う(主語, 問う辺::保持する, 目的語, 割り当て, &関係の問い方::その種類の辺を辿る経路),
            原子命題::マーカーを持つ { 概念, マーカー名 } => self.マーカーの有無を問う(概念, マーカー名, 割り当て),
            原子命題::設計関係へ1つも参加していない { 概念 } => self.参加の有無を問う(概念, 割り当て),
            原子命題::発生する { .. } | 原子命題::遷移する { .. } | 原子命題::到達可能である { .. } => {
                検証結果::未決定(未決定の理由::この検証器が扱わない式を含む(format!("構造の検証器は振る舞いの原子命題を解かない: {}", 原子.表記())))
            }
        }
    }

    /// 主語から目的語へその関係が在るかを、渡された問い方でグラフへ尋ねる。直接の辺と辿る経路の2つの原子が
    /// 同じ節点の解決と同じ証拠の組み立てを通るため、問い方だけを引数で受けて工程を1つに保つ。
    fn 関係の有無を問う(&self, 主語: &項, 辺: 問う辺, 目的語: &項, 割り当て: &束縛の割り当て, 問い方: &関係の問い方) -> 検証結果 {
        let 主語の参照 = match self.項からグラフの節点を求める(主語, 割り当て) {
            Ok(参照) => 参照,
            Err(理由) => return 検証結果::未決定(理由),
        };
        let 目的語の参照 = match self.項からグラフの節点を求める(目的語, 割り当て) {
            Ok(参照) => 参照,
            Err(理由) => return 検証結果::未決定(理由),
        };
        let 表記 = 問い方.表記(&主語の参照, 辺, &目的語の参照);
        if 問い方.グラフへ問う(self.グラフを貸す(), &主語の参照, 辺, &目的語の参照) {
            設計関係を1件見た証拠(&表記)
        } else {
            self.不在に由来する結果を弱める(設計関係が無い反例(&表記, &主語の参照, &目的語の参照), &表記)
        }
    }

    /// 分類を持つのは型だけであるため、`マーカーを持つ` の定義域は型の主語と設計解釈マーカーの名前である。定義域の外は偽でなく未決定で答える。
    /// 偽で答えると、トレイトや処理の主語について分類の不在を「持っていない」と断定し、否定の下で証明済みへ反転する。
    fn マーカーの有無を問う(&self, 概念: &項, マーカー名: &str, 割り当て: &束縛の割り当て) -> 検証結果 {
        let 参照 = match self.項からグラフの節点を求める(概念, 割り当て) {
            Ok(参照) => 参照,
            Err(理由) => return 検証結果::未決定(理由),
        };
        if 参照.種類() != 設計概念の種類::型 {
            return 検証結果::未決定(未決定の理由::問いの定義域の外である(format!("{}は型でなく分類を持たないため、{マーカー名}を持つかを問えない", 参照.表記())));
        }
        let マーカーの参照 = match self.マーカー名からトレイトの節点を求める(マーカー名) {
            Ok(参照) => 参照,
            Err(理由) => return 検証結果::未決定(理由),
        };
        let 表記 = format!("{}は{マーカー名}を持つ", 参照.表記());
        if self.グラフを貸す().分類を貸す().分類がトレイトを含むか(&参照, &マーカーの参照) {
            設計関係を1件見た証拠(&表記)
        } else {
            self.不在に由来する結果を弱める(設計関係が無い反例(&表記, &参照, &マーカーの参照), &表記)
        }
    }

    fn 参加の有無を問う(&self, 概念: &項, 割り当て: &束縛の割り当て) -> 検証結果 {
        let 参照 = match self.項からグラフの節点を求める(概念, 割り当て) {
            Ok(参照) => 参照,
            Err(理由) => return 検証結果::未決定(理由),
        };
        let 表記 = format!("{}は設計関係へ1つも参加していない", 参照.表記());
        if self.グラフを貸す().設計関係へ1つも参加していないか(&参照) {
            self.不在に由来する結果を弱める(設計関係を1件見た証拠(&表記), &表記)
        } else {
            設計関係が無い反例(&表記, &参照, &参照)
        }
    }

    /// 辺が見つからなかったことだけを根拠にした結果を、抽出が設計関係そのものを落としているときに未決定へ落とす。
    ///
    /// **命題が否定の下に置かれているかという状態を、原子の評価へ運ばない。** 運ぶと、原子の解き手と結合の規則を
    /// 分けた設計が壊れ、含意の前件・二重否定・量化の入れ子で符号が反転する判定の誤りが静かに入る。
    /// かわりに原子の結果の向きで弱める。`設計関係が在る`・`設計関係の経路が在る`・保持するの2つの原子・`マーカーを持つ` の反証済みと、
    /// `設計関係へ1つも参加していない` の証明済みは、どちらも辺か分類の事実が見つからなかったことだけを根拠にしている。
    /// この2つを未決定にすると、3値の結合がここから正しく伝播し、否定で反転して証明済みになる経路と、
    /// 全称が不在から反証される経路を同時に塞ぐ。否定・含意・量化の側へ手を入れる必要は無い。
    fn 不在に由来する結果を弱める(&self, 不在から導いた結果: 検証結果, 表記: &str) -> 検証結果 {
        let 欠落 = self.欠落を貸す();
        if !欠落.在るか() {
            return 不在から導いた結果;
        }
        検証結果::未決定(未決定の理由::関係を落とした抽出の欠落が在る(format!("{表記}の答えを辺の不在から導けない: {}", 欠落.説明())))
    }
}
