//! 対象集合をグラフから有限に列挙する工程。
//!
//! **列挙できない対象集合を空の並びで答えない。** 到達可能な状態と到達可能な遷移は遷移モデルが持つ範囲であり、
//! 設計関係グラフからは列挙できない。空で答えると全称が「0件を全部見た」として通ってしまうため、未決定で答える。
//!
//! 抽出が関係を落としていれば、列挙した4つの対象集合も全件とは言えない。

use crate::{数え上げの網羅性, 設計概念, 設計概念の種類, 設計概念への参照, 設計関係の種類, 関係を落とした抽出の欠落};

use super::super::super::evidence::未決定の理由;
use super::super::super::quantification::対象集合;
use super::super::列挙した対象;
use super::構造の検証器;

fn グラフから列挙した網羅性(欠落: &関係を落とした抽出の欠落) -> 数え上げの網羅性 {
    if 欠落.在るか() {
        数え上げの網羅性::抽出の欠落があり全件と言えない { 説明: 欠落.説明() }
    } else {
        数え上げの網羅性::全件を数え上げた
    }
}

impl 構造の検証器<'_> {
    pub(super) fn 対象集合をグラフから列挙する(&self, 対象: &対象集合) -> Result<列挙した対象, 未決定の理由> {
        match 対象 {
            対象集合::全ての設計概念 => Ok(self.全ての節点を列挙する(対象)),
            対象集合::種類で絞った設計概念(種類) => Ok(self.種類の節点を列挙する(対象, *種類)),
            対象集合::マーカーを持つ設計概念 { マーカー名 } => self.マーカーを分類に持つ節点を列挙する(対象, マーカー名),
            対象集合::全ての設計関係の主語(種類) => Ok(self.関係の主語を列挙する(対象, *種類)),
            対象集合::到達可能な状態 | 対象集合::到達可能な遷移 => Err(未決定の理由::有限に列挙できない(format!("設計関係グラフは{}を列挙できない(遷移モデルの範囲である)", 対象.表記()))),
        }
    }

    fn 全ての節点を列挙する(&self, 対象: &対象集合) -> 列挙した対象 {
        let 参照一覧 = self.グラフを貸す().概念一覧().iter().map(設計概念::参照を組む).collect();
        列挙した対象 {
            呼び名: 対象.表記(),
            参照一覧,
            網羅性: グラフから列挙した網羅性(self.欠落を貸す()),
        }
    }

    fn 種類の節点を列挙する(&self, 対象: &対象集合, 種類: 設計概念の種類) -> 列挙した対象 {
        let 参照一覧 = self.グラフを貸す().種類で絞った概念一覧(種類).into_iter().map(設計概念::参照を組む).collect();
        列挙した対象 {
            呼び名: 対象.表記(),
            参照一覧,
            網羅性: グラフから列挙した網羅性(self.欠落を貸す()),
        }
    }

    // 設計解釈マーカーでない名前は分類に入らないため、0件の母集団として答えず、定義域の外の未決定で答える。
    fn マーカーを分類に持つ節点を列挙する(&self, 対象: &対象集合, マーカー名: &str) -> Result<列挙した対象, 未決定の理由> {
        let 分類 = self.グラフを貸す().分類を貸す();
        if 分類.名前の設計解釈マーカー一覧(マーカー名).is_empty() {
            return Err(未決定の理由::問いの定義域の外である(format!("{マーカー名}は設計解釈マーカーでなく、{}を列挙できない", 対象.表記())));
        }
        Ok(列挙した対象 {
            呼び名: 対象.表記(),
            参照一覧: 分類.名前のトレイトを分類に持つ概念一覧(マーカー名).into_iter().cloned().collect(),
            網羅性: グラフから列挙した網羅性(self.欠落を貸す()),
        })
    }

    fn 関係の主語を列挙する(&self, 対象: &対象集合, 種類: 設計関係の種類) -> 列挙した対象 {
        let 参照一覧 = self.グラフを貸す().関係一覧().iter().filter(|関係| 関係.種類 == 種類).map(|関係| 関係.主語.clone()).collect();
        列挙した対象 {
            呼び名: 対象.表記(),
            参照一覧: 重複を1つにまとめる(参照一覧),
            網羅性: グラフから列挙した網羅性(self.欠落を貸す()),
        }
    }
}

// 種類の違う参照は別の対象である。先に現れた順を保ち、反例の割り当てを安定させる。
fn 重複を1つにまとめる(参照一覧: Vec<設計概念への参照>) -> Vec<設計概念への参照> {
    let mut 済み = std::collections::HashSet::new();
    参照一覧.into_iter().filter(|参照| 済み.insert(参照.clone())).collect()
}
