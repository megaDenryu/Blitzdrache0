//! 対象集合をグラフから有限に列挙する工程。
//!
//! **列挙できない対象集合を空の並びで答えない。** 到達可能な状態と到達可能な遷移は遷移モデルが持つ範囲であり、
//! 設計関係グラフからは列挙できない。空で答えると全称が「0件を全部見た」として通ってしまうため、未決定で答える。
//!
//! 列挙できた4つの対象集合はどれも網羅性が `全件を数え上げた` である。グラフの節点と関係は抽出済みの有限の並びであり、
//! 連続量を含まず、打ち切りも行わないためである。

use crate::{数え上げの網羅性, 設計概念, 設計概念の種類, 設計概念の識別子, 設計概念への参照, 設計関係の種類};

use super::super::super::evidence::未決定の理由;
use super::super::super::quantification::{マーカーの名乗り方, 対象集合};
use super::super::列挙した対象;
use super::構造の検証器;

impl 構造の検証器<'_> {
    pub(super) fn 対象集合をグラフから列挙する(&self, 対象: &対象集合) -> Result<列挙した対象, 未決定の理由> {
        match 対象 {
            対象集合::全ての設計概念 => Ok(self.全ての節点を列挙する(対象)),
            対象集合::種類で絞った設計概念(種類) => Ok(self.種類の節点を列挙する(対象, *種類)),
            対象集合::マーカーを持つ設計概念 { マーカー名, 名乗り方 } => Ok(self.マーカーを名乗る節点を列挙する(対象, マーカー名, *名乗り方)),
            対象集合::全ての設計関係の主語(種類) => Ok(self.関係の主語を列挙する(対象, *種類)),
            対象集合::到達可能な状態 | 対象集合::到達可能な遷移 => Err(未決定の理由::有限に列挙できない(format!("設計関係グラフは{}を列挙できない(遷移モデルの範囲である)", 対象.表記()))),
        }
    }

    fn 全ての節点を列挙する(&self, 対象: &対象集合) -> 列挙した対象 {
        let 参照一覧 = self.グラフを貸す().概念一覧().iter().map(設計概念::参照を組む).collect();
        列挙した対象 {
            呼び名: 対象.表記(),
            参照一覧,
            網羅性: 数え上げの網羅性::全件を数え上げた,
        }
    }

    fn 種類の節点を列挙する(&self, 対象: &対象集合, 種類: 設計概念の種類) -> 列挙した対象 {
        let 参照一覧 = self.グラフを貸す().種類で絞った概念一覧(種類).into_iter().map(設計概念::参照を組む).collect();
        列挙した対象 {
            呼び名: 対象.表記(),
            参照一覧,
            網羅性: 数え上げの網羅性::全件を数え上げた,
        }
    }

    fn マーカーを名乗る節点を列挙する(&self, 対象: &対象集合, マーカー名: &str, 名乗り方: マーカーの名乗り方) -> 列挙した対象 {
        let 構文 = 名乗り方.対応する抽出元の構文();
        let 参照一覧 = self
            .グラフを貸す()
            .関係一覧()
            .iter()
            .filter(|関係| 関係.種類 == 設計関係の種類::下位型である && 関係.目的語.識別子().名前 == マーカー名 && 関係.出どころ.構文 == 構文)
            .map(|関係| 関係.主語.clone())
            .collect();
        列挙した対象 {
            呼び名: 対象.表記(),
            参照一覧: 重複を畳む(参照一覧),
            網羅性: 数え上げの網羅性::全件を数え上げた,
        }
    }

    fn 関係の主語を列挙する(&self, 対象: &対象集合, 種類: 設計関係の種類) -> 列挙した対象 {
        let 参照一覧 = self.グラフを貸す().関係一覧().iter().filter(|関係| 関係.種類 == 種類).map(|関係| 関係.主語.clone()).collect();
        列挙した対象 {
            呼び名: 対象.表記(),
            参照一覧: 重複を畳む(参照一覧),
            網羅性: 数え上げの網羅性::全件を数え上げた,
        }
    }
}

/// 同じ概念を指す参照を1件へ畳む。畳む鍵を同一性にするのは、辺の端点が名乗る種類をこの工程の答えへ効かせないためである
/// (種類を鍵に足すと、抽出器が推測で積んだ端点と正しい種類の端点が母集団へ2件並ぶ)。
/// 先に現れた順を保つのは、反例が指す割り当てを実行ごとに変えないためである。
fn 重複を畳む(参照一覧: Vec<設計概念への参照>) -> Vec<設計概念への参照> {
    let mut 済み: std::collections::HashSet<設計概念の識別子> = std::collections::HashSet::new();
    参照一覧.into_iter().filter(|参照| 済み.insert(参照.識別子().clone())).collect()
}
