//! 関係の在り方の問い方と、問うエッジの高さ。受け取るのは主語と問うエッジと目的語、返すのはグラフの答えと、証拠と反例へ入れる表記である。
//!
//! **直接のエッジと辿る経路は別の問いである。** 直接のエッジはそのソースがその関係を宣言しているかを問い、
//! 辿る経路は宣言の連なりで推移的に成り立つかを問う。間接の保持(`旅行者` が `現在地` を持ち、`現在地` が `東西の位置` を持つ)は
//! `旅行者 保持する 東西の位置` という直接のエッジを持たないため、後者でしか成り立たない。
//! 2つを1つの型の選択肢として持つのは、問いの違いが「グラフへ何を尋ねるか」と「説明にどう書くか」の
//! 2箇所へ同時に効き、片方だけを直すと経路で示した証拠が直接のエッジのように読める文になるためである。
//! **問うエッジは、設計関係(設計の高さ)とプリミティブな関係(プリミティブの高さ)のどちらかである。** 2つの高さを1つの問いへ混ぜないため、
//! グラフへは高さごとの別の問いで尋ねる(Issue #193)。

use crate::{プリミティブな関係の種類, 経路の答え, 設計概念の識別用情報, 設計関係の結び付き方, 設計関係グラフ};

/// 関係が在ることをどう問うかの区別。
pub(super) enum 関係の問い方 {
    直接のエッジ,
    その種類のエッジを辿る経路,
}

/// 関係の在り方をグラフへ問うた答え。辿る経路の問いだけが3つ目の答えを返す。
pub(super) enum 関係の問いの答え {
    在る,
    無い,
    割れたノードで先を辿れない(設計概念の識別用情報), // 辿る途中のノードが定義をたどれたノードと空のノードに割れていた
}

/// どの高さのどのエッジを問うかの区別。
#[derive(Clone, Copy)]
pub(super) enum 問うエッジ {
    設計関係(設計関係の結び付き方),
    プリミティブな関係(プリミティブな関係の種類),
}

impl 問うエッジ {
    // 表記に使う関係の語。
    const fn 語(self) -> &'static str {
        match self {
            Self::設計関係(結び付き方) => 結び付き方.語(),
            Self::プリミティブな関係(種類) => 種類.語(),
        }
    }
}

impl 関係の問い方 {
    /// その問い方でグラフへ問うた答え。
    pub(super) fn グラフへ問う(&self, グラフ: &設計関係グラフ, 主語: &設計概念の識別用情報, エッジ: 問うエッジ, 目的語: &設計概念の識別用情報) -> 関係の問いの答え {
        let 直接の答え = |在るか: bool| if 在るか { 関係の問いの答え::在る } else { 関係の問いの答え::無い };
        match (self, エッジ) {
            (Self::直接のエッジ, 問うエッジ::設計関係(結び付き方)) => 直接の答え(グラフ.関係が在るか(主語, 結び付き方, 目的語)),
            (Self::その種類のエッジを辿る経路, 問うエッジ::設計関係(結び付き方)) => グラフ.経路が在るか(主語, &[結び付き方], 目的語).into(),
            (Self::直接のエッジ, 問うエッジ::プリミティブな関係(種類)) => 直接の答え(グラフ.プリミティブな関係を貸す().在るか(主語, 種類, 目的語)),
            (Self::その種類のエッジを辿る経路, 問うエッジ::プリミティブな関係(種類)) => グラフ.プリミティブな関係の経路が在るか(主語, 種類, 目的語).into(),
        }
    }

    /// 証拠と反例の説明へ入れる、何を問うたかの表記。経路で示した答えが直接のエッジと読み違えられないように語を分ける。
    pub(super) fn 表記(&self, 主語: &設計概念の識別用情報, エッジ: 問うエッジ, 目的語: &設計概念の識別用情報) -> String {
        match self {
            Self::直接のエッジ => format!("{} {} {}", 主語.表記(), エッジ.語(), 目的語.表記()),
            Self::その種類のエッジを辿る経路 => format!("{}から{}のエッジを辿って{}へ達する経路", 主語.表記(), エッジ.語(), 目的語.表記()),
        }
    }
}

impl From<経路の答え> for 関係の問いの答え {
    fn from(答え: 経路の答え) -> Self {
        match 答え {
            経路の答え::達する => Self::在る,
            経路の答え::達しない => Self::無い,
            経路の答え::割れたノードで先を辿れない(ノード) => Self::割れたノードで先を辿れない(ノード),
        }
    }
}
