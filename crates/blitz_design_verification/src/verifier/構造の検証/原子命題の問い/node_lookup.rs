//! 項とマーカー名から、グラフに実在する節点への参照を求める工程。
//!
//! **偽の反証を出さないための3つの未決定をこの1箇所が持つ。** 束縛変数へ割り当てが無い・型の定義をたどれず
//! モジュールパスが未解決である・その概念がグラフに無い、のどれかなら未決定の理由を返す。
//! 未解決のモジュールパスを普通の節点として扱うと、抽出器がたどれなかった型についての命題が全部反証される。
//!
//! **実在の判定は識別子と種類の両方で行う。** 項が名乗る種類と違う種類の節点しかグラフに無いなら、その項が指す概念は在らない。
//! 同一性だけで実在を認めると、実在すると答えた直後に辺の照合(こちらは種類まで見る)が空振りし、その空振りが反証済みになる。

use crate::設計概念への参照;

use super::super::super::super::atom::項;
use super::super::super::super::evidence::未決定の理由;
use super::super::super::super::quantification::束縛の割り当て;
use super::super::構造の検証器;

impl 構造の検証器<'_> {
    pub(super) fn 項からグラフの節点を求める(&self, 項: &項, 割り当て: &束縛の割り当て) -> Result<設計概念への参照, 未決定の理由> {
        let Some(参照) = 項.束縛の割り当てから設計概念への参照を求める(割り当て) else {
            return Err(未決定の理由::この検証器が扱わない式を含む(format!("束縛変数{}へ当たる概念が割り当てに無い", 項.表記())));
        };
        if 参照.識別子().Rustの項目でありながら定義をたどれていないか() {
            return Err(未決定の理由::型の定義のモジュールパスが未解決である(
                format!("{}の定義をたどれておらずモジュールパスが空である", 参照.識別子().名前),
            ));
        }
        // 節点の実在は識別子と種類の両方で見る。同一性だけで見ると、項が `型 Foo` を名乗りグラフには `トレイト Foo` しか無い場合に
        // 実在すると答え、続く辺の照合が空振りした結果が反証済みになる。ここで未決定を返せば、その偽の反証が出ない。
        if !self.グラフを貸す().節点が在るか(&参照) {
            return Err(未決定の理由::対象の概念がグラフに無い(参照.表記()));
        }
        Ok(参照)
    }

    /// マーカー名から設計解釈マーカーの節点への参照を求める。名前だけで指すのは、命題の側がマーカーを名前で名指すためである。
    /// 設計解釈マーカーでない名前(`Clone` のような標準のトレイトや、ドメインのトレイト)は分類に入らないため、問いの定義域の外として未決定で答える。
    /// 同じ名前の設計解釈マーカーが2つ以上在るときは一意に決まらないため未決定で答える(黙って先頭を選ばない)。
    pub(super) fn マーカー名からトレイトの節点を求める(&self, マーカー名: &str) -> Result<設計概念への参照, 未決定の理由> {
        let 候補 = self.グラフを貸す().分類を貸す().名前の設計解釈マーカー一覧(マーカー名);
        let マーカー = match 候補.as_slice() {
            [候補1件] => (*候補1件).clone(),
            [] => return Err(未決定の理由::問いの定義域の外である(format!("{マーカー名}は設計解釈マーカーでなく、分類に入らない"))),
            _ => {
                return Err(未決定の理由::この検証器が扱わない式を含む(
                    format!("{マーカー名}という名前の設計解釈マーカーが{}件在り一意に決まらない", 候補.len()),
                ));
            }
        };
        if !self.グラフを貸す().節点が在るか(&マーカー) {
            return Err(未決定の理由::対象の概念がグラフに無い(マーカー.表記()));
        }
        Ok(マーカー)
    }
}
