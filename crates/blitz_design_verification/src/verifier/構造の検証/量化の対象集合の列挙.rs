//! 量化の対象集合をグラフから有限に列挙する工程。
//!
//! **列挙できない量化の対象集合を空の並びで答えない。** 到達可能な状態と到達可能な状態遷移は状態遷移モデルが持つ範囲であり、
//! 設計関係グラフからは列挙できない。空で答えると全称が「0件を全部見た」として通ってしまうため、未決定で答える。
//!
//! 抽出が宣言を落としていれば、列挙した4つの量化の対象集合も全件とは言えない。
//! どの欠落が全件を損なうかは量化の対象集合で違い、対応は `量化の対象集合::列挙が依る答え一覧` が持つ。マーカーを持つ設計概念は付いているマーカーの答えを弱める欠落だけが、ある種類の設計関係の主語は
//! その種類の設計関係の答えを弱める欠落だけが損なう。全ての設計概念と種類で絞った設計概念は、落とした宣言がどれでもノードを欠きうるため、欠落が1件でも在れば損なう。

use crate::{数え上げの網羅性, 設計概念の種類, 設計概念の識別用情報, 設計概念ノード, 設計関係の結び付き方, 関係を落とした抽出の欠落};

use super::super::super::evidence::未決定の理由;
use super::super::super::量化の語彙::量化の対象集合;
use super::super::列挙した対象;
use super::構造の検証器;

// 列挙した並びの網羅性。量化の対象集合の列挙が依る答え(`量化の対象集合::列挙が依る答え一覧`)を弱める欠落が在れば、全件と言えない。
fn グラフから列挙した網羅性(欠落: &関係を落とした抽出の欠落, 対象: &量化の対象集合) -> 数え上げの網羅性 {
    let 依る答え一覧 = 対象.列挙が依る答え一覧();
    if 欠落.どれかの答えを弱めるか(&依る答え一覧) {
        return 数え上げの網羅性::抽出の欠落があり全件と言えない {
            説明: 欠落.答えを弱める件の説明(&依る答え一覧),
        };
    }
    数え上げの網羅性::全件を数え上げた
}

impl 構造の検証器<'_> {
    pub(super) fn 量化の対象集合をグラフから列挙する(&self, 対象: &量化の対象集合) -> Result<列挙した対象, 未決定の理由> {
        match 対象 {
            量化の対象集合::全ての設計概念 => Ok(self.全てのノードを列挙する(対象)),
            量化の対象集合::種類で絞った設計概念(種類) => Ok(self.種類のノードを列挙する(対象, *種類)),
            量化の対象集合::マーカーを持つ設計概念 { マーカー名 } => self.マーカーが付いているノードを列挙する(対象, マーカー名),
            量化の対象集合::全ての設計関係の主語(結び付き方) => Ok(self.関係の主語を列挙する(対象, *結び付き方)),
            量化の対象集合::到達可能な状態 | 量化の対象集合::到達可能な状態遷移 => {
                Err(未決定の理由::有限に列挙できない(format!("設計関係グラフは{}を列挙できない(状態遷移モデルの範囲である)", 対象.表記())))
            }
        }
    }

    fn 全てのノードを列挙する(&self, 対象: &量化の対象集合) -> 列挙した対象 {
        let 参照一覧 = self.グラフを貸す().概念一覧().iter().map(設計概念ノード::参照を組む).collect();
        列挙した対象::生成する(対象.表記(), 参照一覧, グラフから列挙した網羅性(self.欠落を貸す(), 対象))
    }

    fn 種類のノードを列挙する(&self, 対象: &量化の対象集合, 種類: 設計概念の種類) -> 列挙した対象 {
        let 参照一覧 = self.グラフを貸す().ノードを貸す().種類で絞った一覧(種類).into_iter().map(設計概念ノード::参照を組む).collect();
        列挙した対象::生成する(対象.表記(), 参照一覧, グラフから列挙した網羅性(self.欠落を貸す(), 対象))
    }

    // 設計解釈マーカーでない名前は付いているマーカーに含まれないため、0件の母集団として答えず、定義域の外の未決定で答える。
    fn マーカーが付いているノードを列挙する(&self, 対象: &量化の対象集合, マーカー名: &str) -> Result<列挙した対象, 未決定の理由> {
        let 各型に付いているマーカーの一覧 = self.グラフを貸す().各型に付いているマーカーの一覧を貸す();
        if 各型に付いているマーカーの一覧.名前の設計解釈マーカー一覧(マーカー名).is_empty() {
            return Err(未決定の理由::問いの定義域の外である(format!("{マーカー名}は設計解釈マーカーでなく、{}を列挙できない", 対象.表記())));
        }
        Ok(列挙した対象::生成する(
            対象.表記(),
            各型に付いているマーカーの一覧.名前のトレイトが付いている概念一覧(マーカー名).into_iter().cloned().collect(),
            グラフから列挙した網羅性(self.欠落を貸す(), 対象),
        ))
    }

    fn 関係の主語を列挙する(&self, 対象: &量化の対象集合, 結び付き方: 設計関係の結び付き方) -> 列挙した対象 {
        let 参照一覧 = self.グラフを貸す().関係一覧().iter().filter(|関係| 関係.結び付き方() == 結び付き方).map(|関係| 関係.主語().clone()).collect();
        列挙した対象::生成する(対象.表記(), 重複を1つにまとめる(参照一覧), グラフから列挙した網羅性(self.欠落を貸す(), 対象))
    }
}

// 種類の違う参照は別の対象である。先に現れた順を保ち、反例の割り当てを安定させる。
fn 重複を1つにまとめる(参照一覧: Vec<設計概念の識別用情報>) -> Vec<設計概念の識別用情報> {
    let mut 済み = std::collections::HashSet::new();
    参照一覧.into_iter().filter(|参照| 済み.insert(参照.clone())).collect()
}
