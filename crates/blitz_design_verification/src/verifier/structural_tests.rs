fn 型の参照(名前: &str) -> 設計概念への参照 {
    設計概念への参照::型として生成する("blitz_esca::traveler", 名前)
}

fn トレイトの参照(名前: &str) -> 設計概念への参照 {
    設計概念への参照::トレイトとして生成する("blitz_esca::traveler", 名前)
}

fn 関係(主語: 設計概念への参照, 種類: 設計関係の種類, 目的語: 設計概念への参照) -> 設計関係 {
    設計関係 {
        主語,
        種類,
        目的語,
        出どころ: 抽出の出どころ {
            パス: PathBuf::from("crates/blitz_esca/src/traveler.rs"),
            行番号: 1,
            構文: 抽出元の構文::構造体のフィールド,
        },
    }
}

/// 旅行者が旅行者IDを保持し、旅行者IDが旅行者を識別するグラフ。関係へ参加しない概念も1件持つ。
fn 小さなグラフ() -> 設計関係グラフ {
    設計関係グラフ::生成する(
        vec![
            設計概念::型として生成する("blitz_esca::traveler", "旅行者"),
            設計概念::型として生成する("blitz_esca::traveler", "旅行者ID"),
            設計概念::型として生成する("blitz_esca::traveler", "関係へ参加しない型"),
        ],
        vec![関係(型の参照("旅行者"), 設計関係の種類::保持する, 型の参照("旅行者ID")), 関係(型の参照("旅行者ID"), 設計関係の種類::識別する, 型の参照("旅行者"))],
        分類の事実::無い(),
    )
    .グラフ
}

/// 保持が2段だけ繋がったグラフ。`旅行者 → 現在地 → 東西の位置` の2辺を持ち、直接の辺は1本も持たない。
/// 直接の辺で間接の保持を問うたときの反証と、経路で問うたときの証明の違いをここで再現する。
fn 保持が二段のグラフ() -> 設計関係グラフ {
    設計関係グラフ::生成する(
        vec![
            設計概念::型として生成する("blitz_esca::traveler", "旅行者"),
            設計概念::型として生成する("blitz_esca::traveler", "現在地"),
            設計概念::型として生成する("blitz_esca::traveler", "東西の位置"),
        ],
        vec![関係(型の参照("旅行者"), 設計関係の種類::保持する, 型の参照("現在地")), 関係(型の参照("現在地"), 設計関係の種類::保持する, 型の参照("東西の位置"))],
        分類の事実::無い(),
    )
    .グラフ
}

fn 関係の原子(主語: 設計概念への参照, 種類: 設計関係の種類, 目的語: 設計概念への参照) -> 命題 {
    命題::原子から組む(原子命題::設計関係が在る {
        主語: 項::名指した概念(主語),
        種類,
        目的語: 項::名指した概念(目的語),
    })
}

fn 関係の経路の原子(主語: 設計概念への参照, 種類: 設計関係の種類, 目的語: 設計概念への参照) -> 命題 {
    命題::原子から組む(原子命題::設計関係の経路が在る {
        主語: 項::名指した概念(主語),
        種類,
        目的語: 項::名指した概念(目的語),
    })
}
