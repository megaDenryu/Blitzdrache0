use std::path::PathBuf;

use crate::{分類の事実, 抽出の出どころ, 抽出元の構文, 設計概念, 設計概念への参照, 設計関係, 設計関係の種類, 設計関係グラフ};

use super::super::atom::{原子命題, 項};
