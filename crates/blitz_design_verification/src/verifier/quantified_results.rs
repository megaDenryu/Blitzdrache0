//! 量化の畳み込み: 対象集合の要素ごとに本体を検証した結末を、全称と存在の1つの結末へ畳む。
//!
//! 連言と選言の畳み込みと分けるのは、量化の答えが反例へ「どの割り当てで破れたか」を残さなければ人が再現できず、
//! 証拠へ「対象集合の何件を全部見たか」を残さなければ証明済みの根拠が読めないためである。
//!
//! **全称命題の反例と、存在命題の実例は「見た範囲」から得られるが、全称の成立と存在の不在は「見ていない範囲」に依る。**
//! したがって数え上げの網羅性が答えに効くかどうかは命題の形によって非対称である。全称命題の反例と、存在命題の実例は網羅性に関わらず
//! そのまま答えてよく、全称の全件成立と存在命題の実例0件は、網羅性が全件でないときに未決定で答える。
//!
//! **対象集合が0件の全称を証明済みにしない。** 論理としては空集合上の全称は真だが、検査器としては、
//! まだ1件も実装が無いマーカーについての全称が全部通ることになり「反例なし」と「証明済み」を混同する。
//! 0件の全称は `未決定の理由::対象集合が空である` で答える。
//! 参照: `_doc/設計/設計オントロジー.md` 第9節。

mod evidence_building;

use super::super::evidence::{未決定の理由, 検証の方式, 検証結果};
use super::super::quantification::{束縛の割り当て, 束縛変数};
use crate::数え上げの網羅性;

/// 1つの量化について、対象集合の要素ごとの割り当てと、その割り当てで本体を検証した結末の並び。
/// 方式を外から受け取るのは、この畳み込みを構造の検証器と有限全数の検証器が共有するためである。
pub struct 割り当てごとの検証結果一覧 {
    方式: 検証の方式,
    束縛: 束縛変数,
    対象集合の表記: String,
    網羅性: 数え上げの網羅性, // 並べた件数が取りうる値の全部かどうか。見ていない範囲に依る結末の振り分けがこれを読む
    結末一覧: Vec<(束縛の割り当て, 検証結果)>,
}

impl 割り当てごとの検証結果一覧 {
    /// 量化1つの畳み込みの対象を組む。
    pub fn 生成する(方式: 検証の方式, 束縛: &束縛変数, 対象集合の表記: &str, 網羅性: 数え上げの網羅性, 結末一覧: Vec<(束縛の割り当て, 検証結果)>) -> Self {
        Self {
            方式,
            束縛: 束縛.clone(),
            対象集合の表記: 対象集合の表記.to_string(),
            網羅性,
            結末一覧,
        }
    }

    /// 全称へ畳む。1件でも反証済みならその割り当てを反例へ残す(見た範囲の反例は本物の反例である)。
    /// 全件が証明済みのときは、網羅性が全件を数え上げたときだけ証明済みで答える。
    /// 対象集合を列挙した件数が0件なら未決定である。
    pub fn 全称へ畳む(&self) -> 検証結果 {
        if self.結末一覧.is_empty() {
            return 検証結果::未決定(self.対象集合が空である理由());
        }
        if let Some(反証済み) = self.全称の反証済みを1件探す() {
            return 反証済み;
        }
        if let Some(未決定) = self.未決定を1件探す() {
            return 未決定;
        }
        self.見ていない範囲に依る結末(検証結果::証明済み(self.全件を見た証拠("全称の本体が対象集合の全件で成立した")))
    }

    /// 存在へ畳む。存在命題の実例が1件在ればそのまま証明済みで答える(見た範囲で見つかった実例は本物の実例である)。
    /// 実例が0件のときは、網羅性が全件を数え上げたときだけ反証済みで答える。
    pub fn 存在へ畳む(&self) -> 検証結果 {
        if let Some(証明済み) = self.存在の証明済みを1件探す() {
            return 証明済み;
        }
        if self.結末一覧.is_empty() {
            return self.見ていない範囲に依る結末(検証結果::反証済み(self.反例を組む("対象集合が0件である", Vec::new())));
        }
        if let Some(未決定) = self.未決定を1件探す() {
            return 未決定;
        }
        let 説明 = format!("存在の本体が対象集合の{}件の全部で反証された", self.結末一覧.len());
        self.見ていない範囲に依る結末(検証結果::反証済み(self.反例を組む(&説明, Vec::new())))
    }

    /// 見ていない範囲に依る結末を、網羅性で振り分ける。全件を数え上げたならその結末をそのまま返し、
    /// 標本に限るか上限で打ち切ったなら未決定で答える。見ていない値に反例も実例も在りうるためである。
    fn 見ていない範囲に依る結末(&self, 全件を数え上げたときの結末: 検証結果) -> 検証結果 {
        if self.網羅性.全件を数え上げたか() {
            return 全件を数え上げたときの結末;
        }
        検証結果::未決定(未決定の理由::探索の範囲では反例が無い {
            探索した件数: self.結末一覧.len(),
            探索の範囲の説明: format!("対象集合「{}」について{}", self.対象集合の表記, self.網羅性.表記()),
        })
    }

    /// 全称命題の反例は、どの割り当てで破れたかと、その割り当てで内側が見た事実の両方を持つ。
    /// 内側の材料を割り当てで置き換えると、前状態も入力も得られた出来事も落ちて人がその破れへ戻れない。
    fn 全称の反証済みを1件探す(&self) -> Option<検証結果> {
        let (割り当て, 結末) = self.結末一覧.iter().find(|(_, 結末)| 結末.反証済みか())?;
        let 説明 = format!("全称の本体が1件の割り当てで反証された: {}", 結末.表記());
        let mut 再現の材料 = 割り当て.再現の材料へ写す();
        再現の材料.extend(結末.反証済みの再現の材料());
        Some(検証結果::反証済み(self.反例を組む(&説明, 再現の材料)))
    }

    fn 存在の証明済みを1件探す(&self) -> Option<検証結果> {
        let (割り当て, 結末) = self.結末一覧.iter().find(|(_, 結末)| 結末.証明済みか())?;
        Some(検証結果::証明済み(self.存在の証拠を組む(&結末.表記(), 割り当て)))
    }

    fn 未決定を1件探す(&self) -> Option<検証結果> {
        self.結末一覧.iter().find(|(_, 結末)| matches!(結末, 検証結果::未決定(_))).map(|(_, 結末)| 結末.clone())
    }
}
