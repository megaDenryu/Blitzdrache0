#[test]
fn 存在が全件で反証されたときの反例は材料を持たず説明が何をどれだけ見たかを持つ() {
    let グラフ = 小さなグラフ();
    let 検証器 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い());
    let 束縛 = 束縛変数::生成する("x");
    let どの概念も満たさない本体 = 命題::原子から組む(原子命題::設計関係が在る {
        主語: 項::束縛変数(束縛.clone()),
        種類: 設計関係の種類::消費する,
        目的語: 項::名指した概念(型の参照("旅行者")),
    });
    let 存在 = 命題::存在を組む(束縛, 対象集合::全ての設計概念, どの概念も満たさない本体);
    let 検証結果::反証済み(反例) = 検証器.検証する(&存在) else {
        panic!("消費するの関係が1件も無いため、この存在は反証済みでなければならない");
    };
    // 指し示す1件が無いため材料は空でよいが、そのぶん説明が対象集合の呼び名と確かめた件数を持たなければ未決定と区別できない。
    assert!(反例.再現の材料.is_empty(), "存在の反例は指し示す1件を持たないのに材料が入っている: {:?}", 反例.再現の材料);
    assert!(反例.説明.contains("全ての設計概念"), "説明が対象集合の呼び名を持たない: {}", 反例.説明);
    assert!(反例.説明.contains("3件"), "説明が確かめた件数を持たない: {}", 反例.説明);
}

/// その束縛変数が指す概念が設計関係へ1つも参加していない、という原子の命題。
fn 参加していない原子(束縛: &束縛変数) -> 命題 {
    命題::原子から組む(原子命題::設計関係へ1つも参加していない { 概念: 項::束縛変数(束縛.clone()) })
}
