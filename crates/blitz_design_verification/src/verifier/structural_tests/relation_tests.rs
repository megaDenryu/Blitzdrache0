//! 肯定と否定の両方を検査できることと、量化の反例へ割り当てが入ることを固定する試験。

#![allow(clippy::unwrap_used)]

use crate::design_model::設計関係の種類;

use super::super::super::atom::{原子命題, 項};
use super::super::super::evidence::検証結果;
use super::super::super::proposition::命題;
use super::super::super::quantification::{対象集合, 束縛変数};
use super::super::{命題の検証器, 構造の検証器};
use super::{小さなグラフ, 関係の原子};

#[test]
fn 在る関係は証明済みであり無い関係の否定も証明済みである() {
    let グラフ = 小さなグラフ();
    let 検証器 = 構造の検証器::生成する(&グラフ);
    let 在る = 関係の原子("旅行者", 設計関係の種類::保持する, "旅行者ID");
    assert!(検証器.検証する(&在る).証明済みか());
    let 無いの否定 = 関係の原子("旅行者ID", 設計関係の種類::保持する, "旅行者").否定する();
    assert!(検証器.検証する(&無いの否定).証明済みか());
    assert!(検証器.検証する(&在る.否定する()).反証済みか());
}

#[test]
fn 全称の反証済みは反例へ割り当てを残し存在は1件で証明済みになる() {
    let グラフ = 小さなグラフ();
    let 検証器 = 構造の検証器::生成する(&グラフ);
    let 束縛 = 束縛変数::生成する("x");
    let 本体 = 命題::原子から組む(原子命題::設計関係へ1つも参加していない { 概念: 項::束縛変数(束縛.clone()) });
    let 全称 = 命題::全称を組む(束縛.clone(), 対象集合::全ての設計概念, 本体.clone());
    let 検証結果::反証済み(反例) = 検証器.検証する(&全称) else {
        panic!("旅行者が関係へ参加しているため、この全称は反証済みでなければならない");
    };
    assert_eq!(反例.再現の材料.len(), 1);
    assert_eq!(反例.再現の材料[0].0, "x");
    let 存在 = 命題::存在を組む(束縛, 対象集合::全ての設計概念, 本体);
    assert!(検証器.検証する(&存在).証明済みか());
}
