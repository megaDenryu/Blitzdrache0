#[test]
fn 在る関係は証明済みであり無い関係の否定も証明済みである() {
    let グラフ = 小さなグラフ();
    let 検証器 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い());
    let 在る = 関係の原子(型の参照("旅行者ID"), 設計関係の種類::識別する, 型の参照("旅行者"));
    assert!(検証器.検証する(&在る).証明済みか());
    let 無いの否定 = 関係の原子(型の参照("旅行者"), 設計関係の種類::識別する, 型の参照("旅行者ID")).否定する();
    assert!(検証器.検証する(&無いの否定).証明済みか());
    assert!(検証器.検証する(&在る.否定する()).反証済みか());
}

#[test]
fn 保持する関係は設計関係の原子から見えず保持の原子からだけ見える() {
    let グラフ = 小さなグラフ();
    let 検証器 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い());
    assert!(検証器.検証する(&保持の原子(型の参照("旅行者"), 型の参照("旅行者ID"))).証明済みか());
    assert!(検証器.検証する(&保持の原子(型の参照("旅行者ID"), 型の参照("旅行者"))).反証済みか());
    for 種類 in 設計関係の種類::最小語彙() {
        assert!(検証器.検証する(&関係の原子(型の参照("旅行者"), 種類, 型の参照("旅行者ID"))).反証済みか(), "保持する関係が設計関係の{}として見えている", 種類.語());
    }
}

#[test]
fn 保持する関係だけを持つ概念は設計関係へ1つも参加していないと答える() {
    // 保持するはプリミティブの高さの関係であり設計の意味を持たないため、参加に数えない(Issue #193 の段階3)。
    let グラフ = 保持が二段のグラフ();
    let 検証器 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い());
    for 名前 in ["旅行者", "現在地", "東西の位置"] {
        let 参加していない = 命題::原子から組む(原子命題::設計関係へ1つも参加していない {
            概念: 項::名指した概念(型の参照(名前))
        });
        assert!(検証器.検証する(&参加していない).証明済みか(), "{名前}は保持する関係の辺しか持たないのに設計関係へ参加していると答えた");
    }
}

#[test]
fn 全称の反証済みは反例へ割り当てと内側の材料の両方を残す() {
    let グラフ = 小さなグラフ();
    let 検証器 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い());
    let 束縛 = 束縛変数::生成する("x");
    let 全称 = 命題::全称を組む(束縛.clone(), 対象集合::全ての設計概念, 参加していない原子(&束縛));
    let 検証結果::反証済み(反例) = 検証器.検証する(&全称) else {
        panic!("旅行者が関係へ参加しているため、この全称は反証済みでなければならない");
    };
    // 先頭が割り当て(どの概念で破れたか)、続く2件が内側の原子が見た事実(主語と目的語)である。片方だけでは人がその破れへ戻れない。
    let 破れた概念 = 型の参照("旅行者").表記();
    assert_eq!(反例.再現の材料[0], (束縛.名前().to_string(), 破れた概念.clone()), "割り当てが先頭に無い: {:?}", 反例.再現の材料);
    assert_eq!(反例.再現の材料[1], ("主語".to_string(), 破れた概念.clone()), "内側の原子が見た主語が保たれていない: {:?}", 反例.再現の材料);
    assert_eq!(反例.再現の材料[2], ("目的語".to_string(), 破れた概念), "内側の原子が見た目的語が保たれていない: {:?}", 反例.再現の材料);
    assert_eq!(反例.再現の材料.len(), 3, "割り当て1件と内側の材料2件のほかに材料が入っている: {:?}", 反例.再現の材料);
}

