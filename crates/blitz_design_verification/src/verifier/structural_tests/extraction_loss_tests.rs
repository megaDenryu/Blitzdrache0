//! 抽出が設計関係そのものを落としているとき、辺の不在を根拠にした結末が未決定になることを固定する試験。
//!
//! 塞ぎたい経路は2つある。否定の下で反証済みが反転して証明済みになる経路と、全称が不在から反証される経路である。
//! どちらも「辺がグラフに無い」ことだけを根拠にしており、抽出がその辺を落としていたなら根拠にならない。
//! **欠落が無いときに従来どおり反証済みを答えることも同じ数だけ固定する。** 常に未決定へ倒す是正は、
//! 反証済みの退行を捕まえられなくするためである。

#![allow(clippy::unwrap_used)]

use crate::{落とした理由ごとの件数, 設計概念, 設計概念の種類, 設計関係の種類, 設計関係グラフ, 関係を落とした抽出の欠落};

use super::super::super::atom::{原子命題, 項};
use super::super::super::evidence::{未決定の理由, 検証結果};
use super::super::super::proposition::命題;
use super::super::super::quantification::{対象集合, 束縛変数};
use super::super::{命題の検証器, 構造の検証器};
use super::{小さなグラフ, 識別子, 関係の原子};

/// 役割を持つ宣言の名前を読めず関係を1件落とした、という欠落。
fn 関係を1件落とした欠落() -> 関係を落とした抽出の欠落 {
    関係を落とした抽出の欠落::生成する(
        vec![落とした理由ごとの件数 {
            理由の説明: "役割を持つ宣言の名前を読めない".to_string(),
            件数: 1,
        }],
        &[],
    )
}

/// 同じ識別子へ型とトレイトの両方が現れ、節点が2つへ割れたグラフの組み立ての結末から作った欠落。
fn 同一性の衝突だけの欠落() -> 関係を落とした抽出の欠落 {
    let 組み立て = 設計関係グラフ::生成する(vec![設計概念::型として生成する("blitz_esca::traveler", "旅行者"), 設計概念::トレイトとして生成する("blitz_esca::traveler", "旅行者")], Vec::new());
    assert_eq!(組み立て.同一性の衝突一覧.len(), 1, "衝突を1件持つ結末を前提にしている");
    assert_eq!(組み立て.同一性の衝突一覧[0].後から現れた種類, 設計概念の種類::トレイト);
    関係を落とした抽出の欠落::生成する(Vec::new(), &組み立て.同一性の衝突一覧)
}

#[test]
fn 欠落が在るとき無い関係の否定は証明済みにならず未決定になる() {
    let グラフ = 小さなグラフ();
    let 検証器 = 構造の検証器::生成する(&グラフ, 関係を1件落とした欠落());
    let 無いの否定 = 関係の原子("旅行者ID", 設計関係の種類::保持する, "旅行者").否定する();
    assert!(matches!(検証器.検証する(&無いの否定), 検証結果::未決定(未決定の理由::関係を落とした抽出の欠落が在る(_))));
}

#[test]
fn 欠落が無いとき無い関係は従来どおり反証済みを答える() {
    let グラフ = 小さなグラフ();
    let 検証器 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い());
    let 無い = 関係の原子("旅行者ID", 設計関係の種類::保持する, "旅行者");
    assert!(検証器.検証する(&無い).反証済みか());
    assert!(検証器.検証する(&無い.否定する()).証明済みか());
}

#[test]
fn 欠落が在るとき全称は不在から反証されず未決定になる() {
    let グラフ = 小さなグラフ();
    let 全称 = 旅行者IDを保持する全称();
    assert!(構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&全称).反証済みか());
    let 結末 = 構造の検証器::生成する(&グラフ, 関係を1件落とした欠落()).検証する(&全称);
    assert!(matches!(結末, 検証結果::未決定(未決定の理由::関係を落とした抽出の欠落が在る(_))), "{}", 結末.表記());
}

#[test]
fn 欠落が在るとき設計関係へ1つも参加していないの証明は未決定になる() {
    let グラフ = 小さなグラフ();
    let 参加していない = 命題::原子から組む(原子命題::設計関係へ1つも参加していない {
        概念: 項::名指した概念(識別子("関係へ参加しない型")),
    });
    assert!(構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&参加していない).証明済みか());
    let 結末 = 構造の検証器::生成する(&グラフ, 関係を1件落とした欠落()).検証する(&参加していない);
    assert!(matches!(結末, 検証結果::未決定(未決定の理由::関係を落とした抽出の欠落が在る(_))), "{}", 結末.表記());
}

#[test]
fn 同一性の衝突が1件でもあるとき不在に由来する結末は未決定になる() {
    let グラフ = 小さなグラフ();
    let 検証器 = 構造の検証器::生成する(&グラフ, 同一性の衝突だけの欠落());
    let 無い = 関係の原子("旅行者ID", 設計関係の種類::保持する, "旅行者");
    assert!(matches!(検証器.検証する(&無い), 検証結果::未決定(未決定の理由::関係を落とした抽出の欠落が在る(_))));
}

/// 全ての設計概念が旅行者IDを保持する、という全称。旅行者だけが満たし、残る2件は辺が無いため不在から反証される。
fn 旅行者IDを保持する全称() -> 命題 {
    let 束縛 = 束縛変数::生成する("x");
    命題::全称を組む(
        束縛.clone(),
        対象集合::全ての設計概念,
        命題::原子から組む(原子命題::設計関係が在る {
            主語: 項::束縛変数(束縛),
            種類: 設計関係の種類::保持する,
            目的語: 項::名指した概念(識別子("旅行者ID")),
        }),
    )
}
