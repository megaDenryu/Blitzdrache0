//! 直接の辺を問う原子と、辺を辿る経路を問う原子が別の答えを返すことを固定する試験。
//!
//! 上位トレイトの関係は推移的であり、`trait M時間局所状態: M状態` と `trait M状態: M不変データ` が在れば
//! `M時間局所状態` は `M不変データ` の下位型である。**Rustはその直接の辺を宣言しない。** 宣言する必要が無く、
//! コンパイラが推移性を保証するためである。したがって直接の辺で法則を書くと、正しい設計が偽の反証を受ける。
//! 同じ主語と目的語について2つの原子が違う答えを返すことが、この区別が働いている証拠である。

#![allow(clippy::unwrap_used)]

use crate::{設計関係の種類, 関係を落とした抽出の欠落};

use super::super::super::evidence::検証結果;

use super::super::{命題の検証器, 構造の検証器};
use super::{上位トレイトが二段のグラフ, 関係の原子, 関係の経路の原子};

#[test]
fn 二段の上位トレイトは経路の原子で証明済みになる() {
    let グラフ = 上位トレイトが二段のグラフ();
    let 経路 = 関係の経路の原子("M時間局所状態", 設計関係の種類::下位型である, "M不変データ");
    let 結末 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&経路);
    assert!(結末.証明済みか(), "2辺で繋がっているのに経路の原子が証明済みにならなかった: {}", 結末.表記());
}

#[test]
fn 同じ主語と目的語でも直接の辺の原子は反証済みになる() {
    let グラフ = 上位トレイトが二段のグラフ();
    let 直接の辺 = 関係の原子("M時間局所状態", 設計関係の種類::下位型である, "M不変データ");
    let 結末 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&直接の辺);
    assert!(結末.反証済みか(), "直接の辺を宣言していないのに直接の辺の原子が反証済みにならなかった: {}", 結末.表記());
}

#[test]
fn 経路が無い向きでは経路の原子が反証済みになる() {
    let グラフ = 上位トレイトが二段のグラフ();
    let 逆向きの経路 = 関係の経路の原子("M不変データ", 設計関係の種類::下位型である, "M時間局所状態");
    let 結末 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&逆向きの経路);
    assert!(結末.反証済みか(), "辺が逆向きにしか無いのに経路の原子が反証済みにならなかった: {}", 結末.表記());
}

#[test]
fn 経路で示した証拠の説明は経路で答えたことを言う() {
    let グラフ = 上位トレイトが二段のグラフ();
    let 経路 = 関係の経路の原子("M時間局所状態", 設計関係の種類::下位型である, "M不変データ");
    let 検証結果::証明済み(証拠) = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&経路) else {
        panic!("2辺で繋がっているのに証明済みにならなかった");
    };
    assert!(証拠.説明.contains("経路"), "経路で示した証拠が直接の辺のように読める説明になっている: {}", 証拠.説明);
}
