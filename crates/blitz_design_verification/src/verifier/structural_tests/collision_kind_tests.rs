//! 同一性の衝突を含むグラフへ肯定側の問いを投げたとき、検証器が反証済みを答えないことを固定する試験。
//!
//! 種類を照合へ入れた結果、抽出器が種類を取り違えた端点についての問いは辺を見つけられなくなる。その空振りが反証済みになると、
//! 是正が新しい偽の反証を生む。空振りの受け止め方は2つ在り、この試験はその両方と、正しい種類の問いが従来どおり通ることを固定する。
//! 1つは、正しい種類の節点も在る場合であり、同一性の衝突が `関係を落とした抽出の欠落` になって結末を未決定へ倒す。
//! もう1つは、正しい種類の節点が無い場合であり、項から節点を求める工程が `対象の概念がグラフに無い` を返す。

#![allow(clippy::unwrap_used)]

use crate::{設計概念, 設計関係の種類, 設計関係グラフ, 関係を落とした抽出の欠落};

use super::super::super::evidence::{未決定の理由, 検証結果};
use super::super::super::proposition::命題;
use super::super::{命題の検証器, 構造の検証器};
use super::{トレイトの参照, 型の参照, 関係, 関係の原子};

/// `トレイト Foo` だけが `トレイト M` の下位型である辺を持ち、同じ識別子の `型 Foo` も節点として在るグラフ。
/// 組み立ては同一性の衝突を1件数え、その衝突が欠落になる。
fn 衝突を含むグラフと欠落() -> (設計関係グラフ, 関係を落とした抽出の欠落) {
    let 結末 = 設計関係グラフ::生成する(
        vec![
            設計概念::型として生成する("blitz_esca::traveler", "Foo"),
            設計概念::トレイトとして生成する("blitz_esca::traveler", "Foo"),
            設計概念::トレイトとして生成する("blitz_esca::traveler", "M"),
        ],
        vec![関係(トレイトの参照("Foo"), 設計関係の種類::下位型である, トレイトの参照("M"))],
    );
    assert_eq!(結末.同一性の衝突一覧.len(), 1, "この試験の前提である同一性の衝突が1件で起きていない");
    let 欠落 = 関係を落とした抽出の欠落::生成する(Vec::new(), &結末.同一性の衝突一覧);
    assert!(欠落.在るか(), "同一性の衝突が欠落として数えられていない");
    (結末.グラフ, 欠落)
}

#[test]
fn 衝突した識別子の間違った種類への肯定の問いは反証済みでなく未決定になる() {
    let (グラフ, 欠落) = 衝突を含むグラフと欠落();
    let 検証器 = 構造の検証器::生成する(&グラフ, 欠落);
    let 間違った種類の問い = 関係の原子(型の参照("Foo"), 設計関係の種類::下位型である, トレイトの参照("M"));
    let 答え = 検証器.検証する(&間違った種類の問い);
    assert!(!答え.反証済みか(), "辺の空振りが反証済みになっている: {}", 答え.表記());
    assert!(!答え.証明済みか(), "種類の違う辺を借りて証明済みになっている: {}", 答え.表記());
    let 検証結果::未決定(未決定の理由::関係を落とした抽出の欠落が在る(_)) = &答え else {
        panic!("衝突を欠落として受け止めた未決定になっていない: {}", 答え.表記());
    };
}

#[test]
fn 衝突した識別子でも正しい種類への肯定の問いは証明済みのままである() {
    let (グラフ, 欠落) = 衝突を含むグラフと欠落();
    let 検証器 = 構造の検証器::生成する(&グラフ, 欠落);
    let 正しい種類の問い = 関係の原子(トレイトの参照("Foo"), 設計関係の種類::下位型である, トレイトの参照("M"));
    assert!(検証器.検証する(&正しい種類の問い).証明済みか(), "種類の合う辺まで見えなくなっている");
}

#[test]
fn 正しい種類の節点が無い問いは対象の概念がグラフに無いで未決定になる() {
    let 結末 = 設計関係グラフ::生成する(
        vec![設計概念::トレイトとして生成する("blitz_esca::traveler", "Foo"), 設計概念::トレイトとして生成する("blitz_esca::traveler", "M")],
        vec![関係(トレイトの参照("Foo"), 設計関係の種類::下位型である, トレイトの参照("M"))],
    );
    assert!(結末.同一性の衝突一覧.is_empty(), "この試験は衝突が起きない形でなければならない");
    let 検証器 = 構造の検証器::生成する(&結末.グラフ, 関係を落とした抽出の欠落::無い());
    let 節点が無い問い = 関係の原子(型の参照("Foo"), 設計関係の種類::下位型である, トレイトの参照("M"));
    let 答え = 検証器.検証する(&節点が無い問い);
    let 検証結果::未決定(未決定の理由::対象の概念がグラフに無い(_)) = &答え else {
        panic!("種類の合う節点が無いのに未決定で答えていない: {}", 答え.表記());
    };
}
