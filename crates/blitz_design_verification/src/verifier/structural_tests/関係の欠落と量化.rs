//! 関係の端点が欠けて主語が対象集合から消えたとき、量化が見た範囲の証拠だけを答える試験。

use crate::{設計概念, 設計関係の種類, 設計関係グラフ, 関係を落とした抽出の欠落};

use super::super::super::atom::{原子命題, 項};
use super::super::super::evidence::{未決定の理由, 検証結果};
use super::super::super::proposition::命題;
use super::super::super::quantification::{対象集合, 束縛変数};
use super::super::{命題の検証器, 構造の検証器};
use super::{型の参照, 関係};

fn 主語が欠けたグラフ() -> 設計関係グラフ {
    let 概念一覧 = ["A", "B", "Y", "Z"].into_iter().map(|名前| 設計概念::型として生成する("blitz_esca::traveler", 名前)).collect();
    let 関係一覧 = vec![
        関係(型の参照("A"), 設計関係の種類::保持する, 型の参照("X")),
        関係(型の参照("B"), 設計関係の種類::保持する, 型の参照("Y")),
        関係(型の参照("B"), 設計関係の種類::識別する, 型の参照("Z")),
    ];
    設計関係グラフ::生成する(概念一覧, 関係一覧).グラフ
}

fn 関係の主語を量化する(存在か: bool, 否定か: bool) -> 命題 {
    let 束縛 = 束縛変数::生成する("概念");
    let 本体 = 命題::原子から組む(原子命題::設計関係が在る {
        主語: 項::束縛変数(束縛.clone()),
        種類: 設計関係の種類::識別する,
        目的語: 項::名指した概念(型の参照("Z")),
    });
    let 本体 = if 否定か { 本体.否定する() } else { 本体 };
    let 対象 = 対象集合::全ての設計関係の主語(設計関係の種類::保持する);
    if 存在か { 命題::存在を組む(束縛, 対象, 本体) } else { 命題::全称を組む(束縛, 対象, 本体) }
}

#[test]
fn 消えた主語が在る全称は観測済みの本体が全て成立しても未決定になる() {
    let グラフ = 主語が欠けたグラフ();
    let 結末 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&関係の主語を量化する(false, false));
    assert!(matches!(結末, 検証結果::未決定(未決定の理由::探索の範囲では反例が無い { .. })), "{}", 結末.表記());
    assert!(結末.表記().contains("端点"), "{}", 結末.表記());
}

