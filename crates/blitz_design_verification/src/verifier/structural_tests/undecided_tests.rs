//! 偽で答えてはならない3つの場合が未決定になることを固定する試験。
//!
//! 振る舞いの原子命題・空の対象集合の全称・モジュールパスが未解決の節点の3つである。どれも偽へ潰すと、
//! 「反例なし」を「証明済み」と呼ぶか、抽出がたどれなかった型についての命題を偽の反証で落とすことになる。

#![allow(clippy::unwrap_used)]

use crate::{設計概念の種類, 設計概念への参照, 設計関係の種類, 関係を落とした抽出の欠落};

use super::super::super::atom::{原子命題, 項};
use super::super::super::evidence::{未決定の理由, 検証結果};
use super::super::super::proposition::命題;
use super::super::super::quantification::{対象集合, 束縛変数};
use super::super::{命題の検証器, 構造の検証器};
use super::{型の参照, 小さなグラフ, 関係の原子};

#[test]
fn 振る舞いの原子命題は未決定になり偽へ潰れない() {
    let グラフ = 小さなグラフ();
    let 検証器 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い());
    let 発生する = 命題::原子から組む(原子命題::発生する {
        遷移: 項::名指した概念(型の参照("歩行の遷移")),
        イベント: 項::名指した概念(型の参照("移動した")),
    });
    assert!(matches!(検証器.検証する(&発生する), 検証結果::未決定(未決定の理由::この検証器が扱わない式を含む(_))));
}

#[test]
fn 対象集合が空の全称は証明済みにならず未決定になる() {
    let グラフ = 小さなグラフ();
    let 検証器 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い());
    let 全称 = 命題::全称を組む(
        束縛変数::生成する("t"),
        対象集合::種類で絞った設計概念(設計概念の種類::処理),
        関係の原子(型の参照("旅行者"), 設計関係の種類::保持する, 型の参照("旅行者ID")),
    );
    assert!(matches!(検証器.検証する(&全称), 検証結果::未決定(未決定の理由::対象集合が空である(_))));
}

#[test]
fn モジュールパスが未解決の節点に触れた原子命題は未決定になる() {
    let グラフ = 小さなグラフ();
    let 検証器 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い());
    let 未解決 = 命題::原子から組む(原子命題::設計関係が在る {
        主語: 項::名指した概念(設計概念への参照::型として生成する("", "たどれなかった型")),
        種類: 設計関係の種類::保持する,
        目的語: 項::名指した概念(型の参照("旅行者ID")),
    });
    assert!(matches!(検証器.検証する(&未解決), 検証結果::未決定(未決定の理由::型の定義のモジュールパスが未解決である(_))));
}
