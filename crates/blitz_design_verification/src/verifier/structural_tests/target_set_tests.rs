//! マーカーを持つ設計概念の対象集合と `マーカーを持つ` の原子が、辺でなく閉じた分類を読むことを固定する試験。
//!
//! 固定するのは3つである。上位トレイトの宣言(`trait M不変エンティティ: Mエンティティ`)があってもトレイトは母集団へ入らないこと。
//! `M状態` を実装した型は、`M不変データ` を直に実装していなくても上位トレイトの宣言で閉じた分類によって `M不変データ` を持つこと。
//! 分類だけを持ち辺を持たない型は、設計関係へ参加していないと答えられること。

#![allow(clippy::unwrap_used)]

use std::path::PathBuf;

use crate::{マーカーの実装の事実, 上位トレイトの宣言の事実, 事実の出どころ, 分類の事実, 設計概念, 設計概念への参照, 設計関係グラフ, 関係を落とした抽出の欠落};

use super::super::super::atom::{原子命題, 項};
use super::super::super::evidence::{未決定の理由, 検証結果};
use super::super::super::proposition::命題;
use super::super::super::quantification::{対象集合, 束縛変数};
use super::super::{命題の検証器, 構造の検証器};

const 正本のモジュールパス: &str = "blitz_design::marker";

fn 型の参照(名前: &str) -> 設計概念への参照 {
    設計概念への参照::型として生成する("blitz_esca::traveler", 名前)
}

fn トレイトの参照(名前: &str) -> 設計概念への参照 {
    設計概念への参照::トレイトとして生成する(正本のモジュールパス, 名前)
}

fn 出どころ() -> 事実の出どころ {
    事実の出どころ {
        パス: PathBuf::from("crates/blitz_design/src/marker.rs"),
        行番号: 1,
    }
}

/// `trait M不変エンティティ: Mエンティティ` と `trait M状態: M不変データ` を持ち、`旅行者の現在地` が `M状態` だけを実装するグラフ。
/// `Mエンティティ` を実装した型は1件も無い。辺は1本も無い。
fn 分類だけのグラフ() -> 設計関係グラフ {
    let トレイト一覧 = ["Mエンティティ", "M不変エンティティ", "M状態", "M不変データ"].map(|名前| 設計概念::トレイトとして生成する(正本のモジュールパス, 名前));
    let mut 概念一覧 = トレイト一覧.to_vec();
    概念一覧.push(設計概念::型として生成する("blitz_esca::traveler", "旅行者の現在地"));
    let 上位 = |トレイト: &str, 上位トレイト: &str| 上位トレイトの宣言の事実 {
        トレイト: トレイトの参照(トレイト),
        上位トレイト: トレイトの参照(上位トレイト),
        出どころ: 出どころ(),
    };
    let 実装 = マーカーの実装の事実 {
        型: 型の参照("旅行者の現在地"),
        マーカー: トレイトの参照("M状態"),
        出どころ: 出どころ(),
    };
    let 事実 = 分類の事実::生成する(vec![実装], vec![上位("M不変エンティティ", "Mエンティティ"), 上位("M状態", "M不変データ")]);
    設計関係グラフ::生成する(概念一覧, Vec::new(), 事実).グラフ
}

fn マーカーを持つ型についての全称(マーカー名: &str, 本体: impl Fn(項) -> 命題) -> 命題 {
    let 束縛 = 束縛変数::生成する("概念");
    命題::全称を組む(束縛.clone(), 対象集合::マーカーを持つ設計概念 { マーカー名: マーカー名.to_string() }, 本体(項::束縛変数(束縛)))
}

fn マーカーを持つ原子(概念: 項, マーカー名: &str) -> 命題 {
    命題::原子から組む(原子命題::マーカーを持つ {
        概念, マーカー名: マーカー名.to_string()
    })
}

#[test]
fn マーカーを実装した型が0件なら上位トレイトの宣言が在っても全称は未決定になる() {
    let グラフ = 分類だけのグラフ();
    let 全称 = マーカーを持つ型についての全称("Mエンティティ", |概念| マーカーを持つ原子(概念, "Mエンティティ"));
    let 結果 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&全称);
    assert!(
        matches!(結果, 検証結果::未決定(未決定の理由::対象集合が空である(_))),
        "Mエンティティを実装した型が0件なのに未決定にならなかった(上位トレイトの宣言のトレイトを母集団へ入れている): {}",
        結果.表記()
    );
}

#[test]
fn 上位トレイトの宣言で閉じた分類により直に実装していないマーカーも持つ() {
    let グラフ = 分類だけのグラフ();
    let 全称 = マーカーを持つ型についての全称("M不変データ", |概念| マーカーを持つ原子(概念, "M状態"));
    let 結果 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&全称);
    assert!(結果.証明済みか(), "M状態を実装した型がM不変データを持つ母集団へ入っていない: {}", 結果.表記());
    let 直の問い = マーカーを持つ原子(項::名指した概念(型の参照("旅行者の現在地")), "M不変データ");
    assert!(構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&直の問い).証明済みか());
}

#[test]
fn 分類だけを持つ型は設計関係へ参加していないと答える() {
    let グラフ = 分類だけのグラフ();
    let 参加していない = 命題::原子から組む(原子命題::設計関係へ1つも参加していない {
        概念: 項::名指した概念(型の参照("旅行者の現在地")),
    });
    assert!(構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&参加していない).証明済みか(), "分類を辺として参加に数えている");
}

#[test]
fn 持っていないマーカーは欠落が在れば未決定になる() {
    let グラフ = 分類だけのグラフ();
    let 問い = マーカーを持つ原子(項::名指した概念(型の参照("旅行者の現在地")), "Mエンティティ");
    assert!(構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&問い).反証済みか());
    let 欠落 = 関係を落とした抽出の欠落::生成する(
        vec![crate::落とした理由ごとの件数 {
            理由の説明: "上位トレイトの宣言を読めない".to_string(),
            件数: 1,
        }],
        &[],
    );
    let 結果 = 構造の検証器::生成する(&グラフ, 欠落).検証する(&問い);
    assert!(matches!(結果, 検証結果::未決定(未決定の理由::関係を落とした抽出の欠落が在る(_))), "分類の事実を落としたのにラベルの不在で反証した: {}", 結果.表記());
}
