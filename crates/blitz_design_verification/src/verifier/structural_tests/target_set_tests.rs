//! マーカーを持つ設計概念の対象集合が、名乗り方でどう絞られるかを固定する試験。
//!
//! `impl M for 型` と `trait A: M` はどちらも `下位型である` の辺を同じ目的語へ向ける。目的語の名前だけで主語を集めると、
//! そのマーカーを実装した型が1件も無くても下位のトレイトが母集団へ入り、全称が「0件を全部見た」ではなく
//! 「1件以上を全部見た」として証明済みになる。3つの試験はその混同の穴を塞ぐ。

#![allow(clippy::unwrap_used)]

use std::path::PathBuf;

use crate::{抽出の出どころ, 抽出元の構文, 設計概念, 設計概念への参照, 設計関係, 設計関係の種類, 設計関係グラフ, 関係を落とした抽出の欠落};

use super::super::super::atom::{原子命題, 項};
use super::super::super::evidence::{未決定の理由, 検証結果};
use super::super::super::proposition::命題;
use super::super::super::quantification::{マーカーの名乗り方, 対象集合, 束縛変数};
use super::super::{命題の検証器, 構造の検証器};

const 正本のモジュールパス: &str = "blitz_design::marker";

fn 型の参照(名前: &str) -> 設計概念への参照 {
    設計概念への参照::型として生成する(正本のモジュールパス, 名前)
}

fn トレイトの参照(名前: &str) -> 設計概念への参照 {
    設計概念への参照::トレイトとして生成する(正本のモジュールパス, 名前)
}

fn 下位型である辺(主語: 設計概念への参照, 目的語: 設計概念への参照, 構文: 抽出元の構文) -> 設計関係 {
    設計関係 {
        主語,
        種類: 設計関係の種類::下位型である,
        目的語,
        出どころ: 抽出の出どころ {
            パス: PathBuf::from("crates/blitz_design/src/marker.rs"),
            行番号: 1,
            構文,
        },
    }
}

/// `Mエンティティ` は下位のトレイトを1つ持つだけで実装した型を1つも持たず、`M状態` は実装した型を1つ持つだけで
/// 下位のトレイトを1つも持たないグラフ。実物の `crates` の現状(`impl Mエンティティ for` が0件で `trait M不変エンティティ: Mエンティティ` が在る)と同じ形である。
fn 名乗り方が分かれるグラフ() -> 設計関係グラフ {
    設計関係グラフ::生成する(
        vec![
            設計概念::トレイトとして生成する(正本のモジュールパス, "Mエンティティ"),
            設計概念::トレイトとして生成する(正本のモジュールパス, "M不変エンティティ"),
            設計概念::トレイトとして生成する(正本のモジュールパス, "M状態"),
            設計概念::型として生成する(正本のモジュールパス, "旅行者の現在地"),
        ],
        vec![
            下位型である辺(トレイトの参照("M不変エンティティ"), トレイトの参照("Mエンティティ"), 抽出元の構文::上位トレイトの宣言),
            下位型である辺(型の参照("旅行者の現在地"), トレイトの参照("M状態"), 抽出元の構文::設計解釈マーカーの実装),
        ],
    )
    .グラフ
}

fn 名乗り方で絞った全称(マーカー名: &str, 名乗り方: マーカーの名乗り方, 目的語: 設計概念への参照) -> 命題 {
    let 束縛 = 束縛変数::生成する("概念");
    命題::全称を組む(
        束縛.clone(),
        対象集合::マーカーを持つ設計概念 {
            マーカー名: マーカー名.to_string(), 名乗り方
        },
        命題::原子から組む(原子命題::設計関係が在る {
            主語: 項::束縛変数(束縛),
            種類: 設計関係の種類::下位型である,
            目的語: 項::名指した概念(目的語),
        }),
    )
}

#[test]
fn マーカーを実装した型が0件なら下位のトレイトが在っても全称は未決定になる() {
    let グラフ = 名乗り方が分かれるグラフ();
    let 全称 = 名乗り方で絞った全称("Mエンティティ", マーカーの名乗り方::実装した型, トレイトの参照("Mエンティティ"));
    let 結果 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&全称);
    assert!(
        matches!(結果, 検証結果::未決定(未決定の理由::対象集合が空である(_))),
        "Mエンティティを実装した型が0件なのに未決定にならなかった(下位のトレイトを母集団へ入れている): {}",
        結果.表記()
    );
}

#[test]
fn 上位トレイトに持つトレイトで絞ると下位のトレイトが母集団へ入る() {
    let グラフ = 名乗り方が分かれるグラフ();
    let 全称 = 名乗り方で絞った全称("Mエンティティ", マーカーの名乗り方::上位トレイトに持つトレイト, トレイトの参照("Mエンティティ"));
    let 結果 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&全称);
    assert!(結果.証明済みか(), "M不変エンティティが母集団へ入っていない: {}", 結果.表記());
}

#[test]
fn 上位トレイトに持つトレイトで絞るとマーカーを実装した型は母集団へ入らない() {
    let グラフ = 名乗り方が分かれるグラフ();
    let 全称 = 名乗り方で絞った全称("M状態", マーカーの名乗り方::上位トレイトに持つトレイト, トレイトの参照("M状態"));
    let 結果 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&全称);
    assert!(
        matches!(結果, 検証結果::未決定(未決定の理由::対象集合が空である(_))),
        "M状態を実装した型が上位トレイトに持つトレイトの母集団へ混ざっている: {}",
        結果.表記()
    );
}
