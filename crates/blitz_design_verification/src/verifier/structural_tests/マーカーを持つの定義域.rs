//! 原子命題 `マーカーを持つ` が、定義域の外(型でない主語・設計解釈マーカーでない名前)を未決定で答え、型の主語では従来どおり答えることを固定する試験。
//!
//! 分類を持つのは型だけである。トレイトや処理の主語について分類の不在を偽と答えると、欠落が0件のとき反証済みになり、
//! 否定の下では証明済みへ反転する。設計解釈マーカーでない名前(`Clone`)も分類に入らないため、同じく未決定で答える。

use std::path::PathBuf;

use crate::{マーカーの実装の事実, 上位トレイトの宣言の事実, 事実の出どころ, 分類の事実, 設計概念, 設計概念への参照, 設計関係グラフ, 関係を落とした抽出の欠落};

use super::super::super::atom::{原子命題, 項};
use super::super::super::evidence::{未決定の理由, 検証結果};
use super::super::super::proposition::命題;
use super::super::super::quantification::{対象集合, 束縛変数};
use super::super::{命題の検証器, 構造の検証器};

const 正本のモジュールパス: &str = "blitz_design::marker";
const 型のモジュールパス: &str = "blitz_esca::traveler";

fn マーカーの参照(名前: &str) -> 設計概念への参照 {
    設計概念への参照::トレイトとして生成する(正本のモジュールパス, 名前)
}

/// `旅行者の現在地` が `M状態` を実装し、`M状態: M不変データ` の宣言を持つグラフ。処理の節点と `Clone` のトレイトの節点も持つ。
fn 定義域の試験のグラフ() -> 設計関係グラフ {
    let マーカー一覧 = ["M状態", "M不変データ", "Mエンティティ"].map(マーカーの参照).to_vec();
    let mut 概念一覧: Vec<設計概念> = ["M状態", "M不変データ", "Mエンティティ", "Clone"].map(|名前| 設計概念::トレイトとして生成する(正本のモジュールパス, 名前)).to_vec();
    概念一覧.push(設計概念::型として生成する(型のモジュールパス, "旅行者の現在地"));
    概念一覧.push(設計概念::処理として生成する(型のモジュールパス, "旅行者を歩かせる"));
    let 出どころ = || 事実の出どころ {
        パス: PathBuf::from("crates/blitz_esca/src/traveler.rs"),
        行番号: 1,
    };
    let 実装 = マーカーの実装の事実 {
        型: 設計概念への参照::型として生成する(型のモジュールパス, "旅行者の現在地"),
        マーカー: マーカーの参照("M状態"),
        出どころ: 出どころ(),
    };
    let 上位 = 上位トレイトの宣言の事実 {
        トレイト: マーカーの参照("M状態"),
        上位トレイト: マーカーの参照("M不変データ"),
        出どころ: 出どころ(),
    };
    設計関係グラフ::生成する(概念一覧, Vec::new(), 分類の事実::生成する(マーカー一覧, vec![実装], vec![上位])).グラフ
}

fn マーカーを持つ(概念: 設計概念への参照, マーカー名: &str) -> 命題 {
    命題::原子から組む(原子命題::マーカーを持つ {
        概念: 項::名指した概念(概念),
        マーカー名: マーカー名.to_string(),
    })
}

fn 検証する(問い: &命題) -> 検証結果 {
    let グラフ = 定義域の試験のグラフ();
    構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(問い)
}

fn 定義域の外か(結果: &検証結果) -> bool {
    matches!(結果, 検証結果::未決定(未決定の理由::問いの定義域の外である(_)))
}

#[test]
fn トレイトの主語はマーカーを持つかを問えず否定しても証明済みにならない() {
    let 問い = マーカーを持つ(マーカーの参照("M状態"), "M不変データ");
    let 結果 = 検証する(&問い);
    assert!(定義域の外か(&結果), "トレイトの主語へ分類の不在で答えている: {}", 結果.表記());
    let 否定 = 検証する(&問い.否定する());
    assert!(定義域の外か(&否定), "否定の下で分類の不在が証明済みへ反転している: {}", 否定.表記());
}

#[test]
fn 処理の主語はマーカーを持つかを問えない() {
    let 結果 = 検証する(&マーカーを持つ(設計概念への参照::処理として生成する(型のモジュールパス, "旅行者を歩かせる"), "M状態"));
    assert!(定義域の外か(&結果), "処理の主語へ分類の不在で答えている: {}", 結果.表記());
}

#[test]
fn 型の主語は閉じた分類で証明し持たないマーカーで反証する() {
    let 現在地 = 設計概念への参照::型として生成する(型のモジュールパス, "旅行者の現在地");
    assert!(検証する(&マーカーを持つ(現在地.clone(), "M不変データ")).証明済みか());
    assert!(検証する(&マーカーを持つ(現在地, "Mエンティティ")).反証済みか());
}

#[test]
fn 設計解釈マーカーでない名前は原子でも対象集合でも定義域の外になる() {
    let 現在地 = 設計概念への参照::型として生成する(型のモジュールパス, "旅行者の現在地");
    let 原子の結果 = 検証する(&マーカーを持つ(現在地, "Clone"));
    assert!(定義域の外か(&原子の結果), "標準のトレイトの名前へ分類で答えている: {}", 原子の結果.表記());
    let 束縛 = 束縛変数::生成する("概念");
    let 全称 = 命題::全称を組む(
        束縛.clone(),
        対象集合::マーカーを持つ設計概念 { マーカー名: "Clone".to_string() },
        命題::原子から組む(原子命題::設計関係へ1つも参加していない { 概念: 項::束縛変数(束縛) }),
    );
    let 全称の結果 = 検証する(&全称);
    assert!(定義域の外か(&全称の結果), "設計解釈マーカーでない名前の対象集合を列挙している: {}", 全称の結果.表記());
}
