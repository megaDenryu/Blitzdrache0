//! 量化が識別子の同じ別種類の対象を消さないことと、欠けた端点の扱いを固定する。
use super::{トレイトの参照, 型の参照, 関係};
use crate::*;

#[test]
fn 同じ識別子の型とトレイトを全称が両方検査する() {
    let 種類 = 設計関係の種類::下位型である;
    let 結末 = 設計関係グラフ::生成する(
        vec![
            設計概念::型として生成する("blitz_esca::traveler", "Foo"),
            設計概念::トレイトとして生成する("blitz_esca::traveler", "Foo"),
            設計概念::トレイトとして生成する("blitz_esca::traveler", "M"),
            設計概念::トレイトとして生成する("blitz_esca::traveler", "N"),
        ],
        vec![
            関係(トレイトの参照("Foo"), 種類, トレイトの参照("M")),
            関係(型の参照("Foo"), 種類, トレイトの参照("M")),
            関係(トレイトの参照("Foo"), 種類, トレイトの参照("N")),
        ],
    );
    let 欠落 = 関係を落とした抽出の欠落::生成する(Vec::new(), &結末.同一性の衝突一覧);
    let 検証器 = 構造の検証器::生成する(&結末.グラフ, 欠落);
    let 対象 = 対象集合::全ての設計関係の主語(種類);
    let 一覧 = 検証器.対象集合を列挙する(&対象).unwrap();
    assert_eq!(一覧.参照一覧, vec![トレイトの参照("Foo"), 型の参照("Foo")]);
    let 変数 = 束縛変数::生成する("対象");
    let 命題 = 命題::全称を組む(
        変数.clone(),
        対象,
        命題::原子から組む(原子命題::設計関係が在る {
            主語: 項::束縛変数(変数),
            種類,
            目的語: 項::名指した概念(トレイトの参照("N")),
        }),
    );
    assert!(matches!(検証器.検証する(&命題), 検証結果::未決定(_)));
}

#[test]
fn 節点の無い端点は種類の取り違えも欠落として報告する() {
    let 結末 = 設計関係グラフ::生成する(vec![設計概念::型として生成する("blitz_esca::traveler", "Foo")], vec![関係(トレイトの参照("Foo"), 設計関係の種類::保持する, 型の参照("不在"))]);
    assert_eq!(結末.グラフ.節点が無い端点一覧(), &[トレイトの参照("Foo"), 型の参照("不在")]);
    let 検証器 = 構造の検証器::生成する(&結末.グラフ, 関係を落とした抽出の欠落::無い());
    let 孤立 = 命題::原子から組む(原子命題::設計関係へ1つも参加していない {
        概念: 項::名指した概念(型の参照("Foo"))
    });
    assert!(matches!(検証器.検証する(&孤立), 検証結果::未決定(_)));
}

#[test]
fn 節点の無い中継点は経路の証拠にならない() {
    let 甲 = 型の参照("甲");
    let 中継 = 型の参照("中継");
    let 乙 = 型の参照("乙");
    let 種類 = 設計関係の種類::保持する;
    let 結末 = 設計関係グラフ::生成する(
        vec![設計概念::型として生成する("blitz_esca::traveler", "甲"), 設計概念::型として生成する("blitz_esca::traveler", "乙")],
        vec![関係(甲.clone(), 種類, 中継.clone()), 関係(中継, 種類, 乙.clone())],
    );
    assert_eq!(結末.グラフ.関係一覧().len(), 0);
    assert!(!結末.グラフ.経路が在るか(&甲, &[種類], &乙));
    assert!(関係を落とした抽出の欠落::無い().グラフの端点を検査する(&結末.グラフ).在るか());
}
