//! 量化の畳み込みが返す証拠と反例と未決定の理由を組む工程。
//!
//! 触れるフィールドは方式・束縛・対象集合の表記・結末一覧の件数だけであり、結末の中身を読まない。
//! 畳み込みの判断(どの結末を選ぶか)と分けるのは、**どの経路で畳んでも対象集合の要素数が答えへ残る**ことを
//! この1箇所で守るためである。件数を呼び出し側で綴ると、経路を1つ足したときにそこだけ件数の無い答えになる。

use super::super::super::evidence::{反例, 未決定の理由, 証拠};
use super::super::super::quantification::束縛の割り当て;
use super::割り当てごとの検証結果一覧;

impl 割り当てごとの検証結果一覧 {
    /// 対象集合を列挙した件数が0件であることを表す未決定の理由。束縛変数の名前と対象集合の表記を残す。
    pub(super) fn 対象集合が空である理由(&self) -> 未決定の理由 {
        未決定の理由::対象集合が空である(format!("全称の対象集合「{}」を列挙した件数が0件である(束縛は?{})", self.対象集合の表記, self.束縛.名前()))
    }

    /// 反例を組む。説明の末尾へ対象集合の表記と要素数を必ず添える。
    pub(super) fn 反例を組む(&self, 説明: &str, 再現の材料: Vec<(String, String)>) -> 反例 {
        反例 {
            方式: self.方式,
            説明: format!("{説明}(対象集合「{}」は{}件)", self.対象集合の表記, self.結末一覧.len()),
            再現の材料,
        }
    }

    /// 全称が全件で成立したときの証拠を組む。見た対象の件数へ列挙した要素数を入れる。
    pub(super) fn 全件を見た証拠(&self, 説明: &str) -> 証拠 {
        証拠 {
            方式: self.方式,
            見た対象の件数: self.結末一覧.len(),
            説明: format!("{説明}(対象集合「{}」の{}件)", self.対象集合の表記, self.結末一覧.len()),
        }
    }

    /// 存在が1件で成立したときの証拠を組む。どの割り当てで成立したかを説明へ残す。
    pub(super) fn 存在の証拠を組む(&self, 本体の説明: &str, 割り当て: &束縛の割り当て) -> 証拠 {
        let 材料 = 割り当て.再現の材料へ写す().into_iter().map(|(名前, 値)| format!("?{名前}={値}")).collect::<Vec<String>>().join(", ");
        証拠 {
            方式: self.方式,
            見た対象の件数: self.結末一覧.len(),
            説明: format!("存在の本体が{材料}で成立した(対象集合「{}」の{}件を見た): {本体の説明}", self.対象集合の表記, self.結末一覧.len()),
        }
    }
}
