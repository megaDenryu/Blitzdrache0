//! 3値(証明済み・反証済み・未決定)の論理結合の規則。
//!
//! 触れるのは `検証結果` の3つの選択肢だけであり、グラフも遷移モデルも読まない。どの検証器もこの規則を共有するため、
//! 検証器ごとに判定を書き写すと、片方だけが未決定を偽へ潰した食い違いが絵に出るまで見つからない。
//! `検証結果` の型そのものは `super::super::evidence` が所有し、このファイルはその型の3値論理の演算を所有する。
//!
//! **未決定は黙って偽へ潰れない。** 連言は反証済みが1つでも在るときだけ反証済みであり、未決定が混じった連言は未決定である。
//! 参照: `_doc/設計/設計オントロジー.md` 第9節。

use super::super::evidence::{反例, 検証の方式, 検証結果, 証拠};

/// 1つの論理結合の子の命題を検証した結果の並びと、それを判定した結果が名乗る検証の方式。
/// 方式を外から受け取るのは、この判定を構造の検証器と有限全数の検証器が共有し、片方の方式を固定で綴ると
/// もう片方の答えが自分の方式を名乗れなくなるためである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 子の命題の検証結果一覧 {
    方式: 検証の方式,
    検証結果一覧: Vec<検証結果>,
}

impl 検証結果 {
    /// 証明済みと反証済みを入れ替える。未決定は理由のまま未決定である。
    pub fn 否定へ反転する(self) -> Self {
        match self {
            Self::証明済み(証拠) => Self::反証済み(反例 {
                方式: 証拠.方式,
                説明: format!("否定の本体が成立した: {}", 証拠.説明),
                再現の材料: Vec::new(),
            }),
            Self::反証済み(反例) => Self::証明済み(証拠 {
                方式: 反例.方式,
                見た対象の件数: 1,
                説明: format!("否定の本体の反例を1件見た: {}", 反例.説明),
            }),
            Self::未決定(理由) => Self::未決定(理由),
        }
    }

    /// この結果を含意の前件としたとき、後件を読まずに含意の結果が決まるならそれを返す。
    /// 前件が反証済みなら証明済み(空虚な成立)であり、前件が未決定なら含意も未決定である。
    /// 前件が証明済みのときだけ値なしを返し、呼び出し側が後件を解いてその結果をそのまま含意の結果にする。
    pub fn 前件だけで含意が決まる結果を求める(self) -> Option<Self> {
        match self {
            Self::反証済み(反例) => Some(Self::証明済み(証拠 {
                方式: 反例.方式,
                見た対象の件数: 0,
                説明: format!("含意の前件が成立しないため空虚に成立する: {}", 反例.説明),
            })),
            Self::未決定(理由) => Some(Self::未決定(理由)),
            Self::証明済み(_) => None,
        }
    }
}

impl 子の命題の検証結果一覧 {
    /// 方式と子の結果の並びから判定の対象を組む。
    pub fn 生成する(方式: 検証の方式, 検証結果一覧: Vec<検証結果>) -> Self {
        Self { 方式, 検証結果一覧 }
    }

    /// 連言として判定する。1つでも反証済みならその反例を返し、全部証明済みなら証明済み、未決定が混じれば未決定である。
    pub fn 連言として判定する(&self) -> 検証結果 {
        if let Some(反証済み) = self.検証結果一覧.iter().find(|結果| 結果.反証済みか()) {
            return 反証済み.clone();
        }
        match self.未決定を1件探す() {
            Some(未決定) => 未決定,
            None => 検証結果::証明済み(self.全件を見た証拠("連言の全ての項が成立した")),
        }
    }

    /// 選言として判定する。1つでも証明済みならその証拠を返し、全部反証済みなら反証済み、未決定が混じれば未決定である。
    pub fn 選言として判定する(&self) -> 検証結果 {
        if let Some(証明済み) = self.検証結果一覧.iter().find(|結果| 結果.証明済みか()) {
            return 証明済み.clone();
        }
        match self.未決定を1件探す() {
            Some(未決定) => 未決定,
            None => 検証結果::反証済み(反例 {
                方式: self.方式,
                説明: format!("選言の{}件の項が全て反証された: {}", self.検証結果一覧.len(), self.反証された項の説明を繋ぐ()),
                再現の材料: Vec::new(),
            }),
        }
    }

    fn 未決定を1件探す(&self) -> Option<検証結果> {
        self.検証結果一覧.iter().find(|結果| matches!(結果, 検証結果::未決定(_))).cloned()
    }

    /// 選言が全件で反証されたときの説明へ入れる、項ごとの結果の表記。
    /// 再現の材料を空にできるのは、指し示す1件が無い代わりに説明が何をどれだけ見たかを持つときだけである。
    fn 反証された項の説明を繋ぐ(&self) -> String {
        self.検証結果一覧.iter().map(検証結果::表記).collect::<Vec<String>>().join(" / ")
    }

    fn 全件を見た証拠(&self, 説明: &str) -> 証拠 {
        証拠 {
            方式: self.方式,
            見た対象の件数: self.検証結果一覧.len(),
            説明: format!("{説明}({}件)", self.検証結果一覧.len()),
        }
    }
}
