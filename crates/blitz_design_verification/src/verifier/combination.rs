//! 結合を解く工程: 命題の木を辿り、原子と対象集合の解き手へ葉を尋ねて結合の規則で1つの結末へ畳む。
//!
//! この工程が結合の規則の唯一の正本である。構造の検証器と有限全数の検証器はどちらもこの工程へ委譲するため、
//! 3値の伝わり方(特に未決定が偽へ潰れないこと)を検証器ごとに書き写さない。
//! 3値の畳み込みそのものは `super::three_valued` と `super::quantified_results` が所有し、この工程は
//! 命題の木のどの節点でどちらの畳み込みを呼ぶかだけを決める。
//! 参照: `_doc/設計/設計オントロジー.md` 第9節。

use super::super::evidence::{未決定の理由, 検証結果};
use super::super::proposition::命題;
use super::super::quantification::{対象集合, 束縛の割り当て, 束縛変数};
use super::quantified_results::割り当てごとの検証結果一覧;
use super::three_valued::子の命題の検証結果一覧;
use super::原子と対象集合の解き手;

/// 原子と対象集合の解き手を借りて、命題の木の結合を解く工程。
pub struct 結合を解く工程<'解き手>(&'解き手 dyn 原子と対象集合の解き手);

impl<'解き手> 結合を解く工程<'解き手> {
    /// 解き手を借りて工程を組む。
    pub fn 生成する(解き手: &'解き手 dyn 原子と対象集合の解き手) -> Self {
        Self(解き手)
    }

    /// 命題1つを解く。量化の外側であるため、空の束縛の割り当てから始める。
    pub fn 命題を解く(&self, 命題: &命題) -> 検証結果 {
        self.割り当てのもとで解く(命題, &束縛の割り当て::空を生成する())
    }

    fn 割り当てのもとで解く(&self, 命題: &命題, 割り当て: &束縛の割り当て) -> 検証結果 {
        match 命題 {
            命題::原子(原子) => self.0.原子を解く(原子, 割り当て),
            命題::否定(本体) => self.割り当てのもとで解く(本体, 割り当て).否定へ反転する(),
            命題::連言(項一覧) => self.項一覧を解く(項一覧, 割り当て).連言へ畳む(),
            命題::選言(項一覧) => self.項一覧を解く(項一覧, 割り当て).選言へ畳む(),
            命題::含意 { 前件, 後件 } => self.含意を解く(前件, 後件, 割り当て),
            命題::全称 { 束縛, 対象集合, 本体 } => match self.量化の結末一覧を組む(束縛, 対象集合, 本体, 割り当て) {
                Ok(一覧) => 一覧.全称へ畳む(),
                Err(理由) => 検証結果::未決定(理由),
            },
            命題::存在 { 束縛, 対象集合, 本体 } => match self.量化の結末一覧を組む(束縛, 対象集合, 本体, 割り当て) {
                Ok(一覧) => 一覧.存在へ畳む(),
                Err(理由) => 検証結果::未決定(理由),
            },
        }
    }

    /// 含意を解く。前件だけで結末が決まるならそれを返し、決まらない(前件が証明済みの)ときだけ後件を解く。
    /// 後件の反証済みはそのまま含意の反証済みとして返り、後件の反例が呼び出し元へ届く。
    fn 含意を解く(&self, 前件: &命題, 後件: &命題, 割り当て: &束縛の割り当て) -> 検証結果 {
        let 前件の結末 = self.割り当てのもとで解く(前件, 割り当て);
        match 前件の結末.前件だけで含意が決まる結末を求める() {
            Some(結末) => 結末,
            None => self.割り当てのもとで解く(後件, 割り当て),
        }
    }

    fn 項一覧を解く(&self, 項一覧: &[命題], 割り当て: &束縛の割り当て) -> 子の命題の検証結果一覧 {
        let 結末一覧 = 項一覧.iter().map(|項| self.割り当てのもとで解く(項, 割り当て)).collect();
        子の命題の検証結果一覧::生成する(self.0.方式(), 結末一覧)
    }

    fn 量化の結末一覧を組む(&self, 束縛: &束縛変数, 対象: &対象集合, 本体: &命題, 割り当て: &束縛の割り当て) -> Result<割り当てごとの検証結果一覧, 未決定の理由> {
        let 列挙 = self.0.対象集合を列挙する(対象)?;
        let 結末一覧 = 列挙
            .識別子一覧
            .iter()
            .map(|識別子| {
                let 足した割り当て = 割り当て.束縛を1件足す(束縛, 識別子);
                let 結末 = self.割り当てのもとで解く(本体, &足した割り当て);
                (足した割り当て, 結末)
            })
            .collect();
        Ok(割り当てごとの検証結果一覧::生成する(self.0.方式(), 束縛, &列挙.呼び名, 列挙.網羅性.clone(), 結末一覧))
    }
}
