//! 構造の検証器: 設計関係グラフを相手に、構造の原子命題と対象集合の列挙を答える解き手。
//!
//! グラフを借りて保持するのは、検証器の口 `検証する` が命題1つだけを受けるためである。グラフを引数で運ばせると
//! 検証器を足すたびに口の署名が変わり、記号実行とSMTの検証器が同じ口に載らなくなる。
//!
//! **結合の場合分けをこの型が持たない。** 否定・連言・選言・含意・全称・存在の規則の正本は `super::結合を解く工程` にあり、
//! この型が実装するのは原子と対象集合の解き手の3つの口だけである。
//! 参照: `_doc/設計/設計オントロジー.md` 第9節。

mod atom;
mod target_set;

use crate::設計関係グラフ;

use super::super::atom::原子命題;
use super::super::evidence::{未決定の理由, 検証の方式, 検証結果};
use super::super::proposition::命題;
use super::super::quantification::{対象集合, 束縛の割り当て};
use super::{列挙した対象, 原子と対象集合の解き手, 命題の検証器, 結合を解く工程};

/// 設計関係グラフだけを相手にする検証器。振る舞いの原子命題は解かず未決定で答える。
pub struct 構造の検証器<'グラフ> {
    グラフ: &'グラフ 設計関係グラフ,
}

impl<'グラフ> 構造の検証器<'グラフ> {
    /// 抽出済みのグラフを借りて検証器を組む。
    pub fn 生成する(グラフ: &'グラフ 設計関係グラフ) -> Self {
        Self { グラフ }
    }

    /// 原子の評価と対象集合の列挙が読むグラフ。同じ木の内側だけへ貸す。
    pub(super) fn グラフを貸す(&self) -> &設計関係グラフ {
        self.グラフ
    }
}

impl 原子と対象集合の解き手 for 構造の検証器<'_> {
    fn 方式(&self) -> 検証の方式 {
        検証の方式::設計関係グラフ
    }

    fn 原子を解く(&self, 原子: &原子命題, 割り当て: &束縛の割り当て) -> 検証結果 {
        self.原子命題をグラフへ問う(原子, 割り当て)
    }

    fn 対象集合を列挙する(&self, 対象: &対象集合) -> Result<列挙した対象, 未決定の理由> {
        self.対象集合をグラフから列挙する(対象)
    }
}

impl 命題の検証器 for 構造の検証器<'_> {
    fn 検証する(&self, 命題: &命題) -> 検証結果 {
        結合を解く工程::生成する(self).命題を解く(命題)
    }
}
