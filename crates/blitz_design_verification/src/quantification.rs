//! 量化の語彙: 束縛変数・対象集合・束縛の割り当て(Issue #173。層3のうち全称と存在が要る3つ)。
//!
//! 量化の命題は「どの範囲の概念について問うか」を対象集合で名指し、その範囲の1件を束縛変数へ当てて本体を評価する。
//! 対象集合を反復子でなく列挙として持つのは、検証器がその範囲を有限に列挙できたかどうかを結末へ残すためであり、
//! 列挙できない範囲(到達可能な状態と到達可能な遷移)を構造の検証器が偽で答えることを型の側で止めるためである。
//! 参照: `_doc/設計/設計オントロジー.md` 第7節。

use crate::{抽出元の構文, 設計概念の種類, 設計概念への参照, 設計関係の種類};

/// 量化が本体へ当てる変数。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct 束縛変数(String);

/// 量化が走る範囲。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 対象集合 {
    /// グラフの全ての節点。
    全ての設計概念,
    /// 型・トレイト・処理のうち1つの種類の節点。
    種類で絞った設計概念(設計概念の種類),
    /// その名前のトレイトへ `下位型である` で結ばれた節点のうち、名乗り方で絞った節点。
    マーカーを持つ設計概念 {
        /// マーカーに立てたトレイトの名前。
        マーカー名: String,
        /// そのマーカーをどの構文で名乗っているか。
        名乗り方: マーカーの名乗り方,
    },
    /// その種類の設計関係の主語に立つ節点。
    全ての設計関係の主語(設計関係の種類),
    /// 遷移モデルの到達可能な状態。構造の検証器はこれを列挙できない。
    到達可能な状態,
    /// 遷移モデルの到達可能な遷移。構造の検証器はこれを列挙できない。
    到達可能な遷移,
}

/// 設計概念がそのマーカーをどの構文で名乗っているかの区別。
///
/// **種類ではなく構文で絞る。** `impl M for 型` と `trait A: M` はどちらも `下位型である` の辺を同じ目的語へ向けるため、
/// 目的語の名前だけで主語を集めると、そのマーカーを実装した型が1件も無くても下位のトレイトが母集団へ入る。
/// 設計概念の種類で絞る形を採らないのは、識別子から種類を引く照会が要り、その照会の一意性に依存するためである。
/// 抽出の出どころの構文は辺が自分で持つため、照会を要しない。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum マーカーの名乗り方 {
    /// `impl M for 型` でそのマーカーを実装した型。
    実装した型,
    /// `trait A: M` でそのマーカーを上位トレイトに持つトレイト。
    上位トレイトに持つトレイト,
}

/// 束縛変数から設計概念への参照への対応。入れ子の量化のため、1件足した新しい割り当てを返す形で持つ。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct 束縛の割り当て {
    対応: Vec<(束縛変数, 設計概念への参照)>,
}

impl 束縛変数 {
    /// 変数の名前から束縛変数を組む。
    pub fn 生成する(名前: &str) -> Self {
        Self(名前.to_string())
    }

    /// 変数の名前。命題の表記と反例の再現の材料がこの文字列を使う。
    pub fn 名前(&self) -> &str {
        &self.0
    }
}

impl 対象集合 {
    /// 人が読む1行の表記。未決定の理由と反例の説明がこの表記を使う。
    pub fn 表記(&self) -> String {
        match self {
            Self::全ての設計概念 => "全ての設計概念".to_string(),
            Self::種類で絞った設計概念(種類) => format!("種類が{種類:?}の設計概念"),
            Self::マーカーを持つ設計概念 { マーカー名, 名乗り方 } => 名乗り方.対象集合の表記を組む(マーカー名),
            Self::全ての設計関係の主語(種類) => format!("{}の関係の主語", 種類.語()),
            Self::到達可能な状態 => "到達可能な状態".to_string(),
            Self::到達可能な遷移 => "到達可能な遷移".to_string(),
        }
    }
}

impl マーカーの名乗り方 {
    /// この名乗り方が読み取る、設計関係の抽出元の構文。
    pub const fn 対応する抽出元の構文(self) -> 抽出元の構文 {
        match self {
            Self::実装した型 => 抽出元の構文::設計解釈マーカーの実装,
            Self::上位トレイトに持つトレイト => 抽出元の構文::上位トレイトの宣言,
        }
    }

    /// そのマーカー名についての対象集合の、人が読む1行の表記。
    pub fn 対象集合の表記を組む(self, マーカー名: &str) -> String {
        match self {
            Self::実装した型 => format!("{マーカー名}を実装した型"),
            Self::上位トレイトに持つトレイト => format!("{マーカー名}を上位トレイトに持つトレイト"),
        }
    }
}

impl 束縛の割り当て {
    /// 1件も当てていない割り当てを組む。量化の外側の命題の評価がここから始まる。
    pub fn 空を生成する() -> Self {
        Self::default()
    }

    /// この割り当てへ1件足した新しい割り当てを返す。元の割り当ては変えない。
    pub fn 束縛を1件足す(&self, 束縛: &束縛変数, 概念: &設計概念への参照) -> Self {
        let mut 対応 = self.対応.clone();
        対応.retain(|(在る束縛, _)| 在る束縛 != 束縛);
        対応.push((束縛.clone(), 概念.clone()));
        Self { 対応 }
    }

    /// その束縛変数へ当たっている概念。当てていなければ値なしを返す。
    pub fn 束縛変数に当たる概念を求める(&self, 束縛: &束縛変数) -> Option<&設計概念への参照> {
        self.対応.iter().find(|(在る束縛, _)| 在る束縛 == 束縛).map(|(_, 概念)| 概念)
    }

    /// いまこの割り当てが当てている概念の全件。どの束縛変数に当たっているかを問わずに当たっている概念そのものを要る側が読む。
    ///
    /// **この口が無いと、当てた概念を再現の材料の文字列から引き当てることになる。** 有限全数の検証器の `遷移する` の原子は、
    /// 命題の側がどの束縛変数へ遷移を当てたかを知らないまま、割り当ての中の遷移を1件見つける必要がある。
    /// 表記で引き当てると、表記の文言を変えただけで引き当てが静かに外れ、原子が未決定へ落ちる。
    pub fn 当たっている概念一覧(&self) -> Vec<&設計概念への参照> {
        self.対応.iter().map(|(_, 概念)| 概念).collect()
    }

    /// 反例の再現の材料へ入れる、束縛変数の名前と概念の表記の対の並び。
    pub fn 再現の材料へ写す(&self) -> Vec<(String, String)> {
        self.対応.iter().map(|(束縛, 概念)| (束縛.名前().to_string(), 概念.表記())).collect()
    }
}
