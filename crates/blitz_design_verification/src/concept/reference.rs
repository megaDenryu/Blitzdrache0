//! 設計概念への参照とは、設計関係の端点と命題の項と量化の割り当てが指し示す、1つの設計概念への指し先のことである。
//! 設計概念の識別子(同一性)と設計概念の種類の組であり、指し先がグラフに実在するとは限らない。
//!
//! **識別子の側へ種類を入れず、参照の側が種類を持つ。** 識別子へ種類を入れると、同じ識別子へ種類の違う概念が現れるという事象が
//! 原理的に起こらなくなり、`設計関係グラフ` の組み立てが数える同一性の衝突が到達しない枝になる。そのうえ抽出器は目的語の種類を
//! 推測しており(関数の役割の規則は、役割の型引数から出した目的語を無条件に型として積む)、推測で積んだ節点と正しい種類の節点が
//! 別の節点へ割れて辺が散る。したがって同一性は4つ組のまま残し、端点の側が種類を運ぶ。この2つを両立させる形はこれだけである。
//!
//! **節点(`設計概念`)と参照は同じ組を持つが別の概念である。** 節点はグラフに実在する1件であり、参照はその1件を指す辺と項の端点である。
//! 節点は参照を包んだ newtype であり、節点が在ることは参照が在ることより強い主張である。
//!
//! **2つの参照が同じ1件を指すかの判定は、値の等価(`==`)である。** 等価は識別子と種類の両方を見るため、
//! `型 Foo` を指す参照と `トレイト Foo` を指す参照は等しくない。設計関係グラフの照合も節点の実在の判定もこの等価を使う。
//! 種類を見ずに識別子だけで照合すると、`トレイト Foo` へ張った辺を `型 Foo` についての問いが借りて証明済みを答える。
//! 識別子だけの一致を見たい工程(辺の端点の重複を畳む工程)は、識別子を取り出して自分で比べる。
//! 参照: `_doc/設計/設計オントロジー.md` 第6節。

use super::identifier::設計概念の識別子;
use super::{Rustの項目の種類, 設計概念の種類};

/// 設計関係の端点と命題の項が指す、1つの設計概念への参照。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct 設計概念への参照 {
    識別子: 設計概念の識別子,
    種類: 設計概念の種類,
}

impl 設計概念への参照 {
    /// Rustのソースに定義が在る項目への参照を組む。識別子の名前空間をRustの項目へ据え直すため、名前空間と種類は必ず揃う。
    #[allow(non_snake_case)] // 日本語の識別子に含むASCIIの大文字はRustの命名規則の検査に掛かる。言語の名前をそのまま使う。
    pub fn Rustの項目として生成する(識別子: 設計概念の識別子, 種類: Rustの項目の種類) -> Self {
        Self {
            識別子: 識別子.名前空間をRustの項目へ据える(),
            種類: 種類.設計概念の種類へ写す(),
        }
    }

    /// 実行時にだけ存在するドメインの概念への参照を組む。名前空間と種類の両方をここで同時に据える。
    pub fn 実行時のドメイン概念として生成する(名前の空間: &str, 名前: &str) -> Self {
        Self {
            識別子: 設計概念の識別子::実行時のドメイン概念として生成する(名前の空間, 名前),
            種類: 設計概念の種類::実行時のドメイン概念,
        }
    }

    /// 型への参照を組む。
    pub fn 型として生成する(モジュールパス: &str, 名前: &str) -> Self {
        Self::Rustの項目として生成する(設計概念の識別子::Rustの項目として生成する(モジュールパス, 名前), Rustの項目の種類::型)
    }

    /// トレイトへの参照を組む。
    pub fn トレイトとして生成する(モジュールパス: &str, 名前: &str) -> Self {
        Self::Rustの項目として生成する(設計概念の識別子::Rustの項目として生成する(モジュールパス, 名前), Rustの項目の種類::トレイト)
    }

    /// 処理への参照を組む。
    pub fn 処理として生成する(モジュールパス: &str, 名前: &str) -> Self {
        Self::Rustの項目として生成する(設計概念の識別子::Rustの項目として生成する(モジュールパス, 名前), Rustの項目の種類::処理)
    }

    /// この参照が指す概念の同一性。
    pub fn 識別子(&self) -> &設計概念の識別子 {
        &self.識別子
    }

    /// この参照が名乗る種類。
    pub const fn 種類(&self) -> 設計概念の種類 {
        self.種類
    }

    /// 人が読む1行の表記。証拠と反例と違反の報告がこの表記を使う。
    pub fn 表記(&self) -> String {
        self.識別子.表記()
    }
}
