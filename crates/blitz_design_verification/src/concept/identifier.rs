//! 設計概念の同一性。名前空間と定義のモジュールパスと所有者の並びと名前の4つ組である。
//!
//! ノードそのもの(`設計概念ノード`)から分けるのは、同一性がノードを持たない場所(設計関係の主語と目的語、命題の項、遷移モデルの状態と入力)で
//! 単独に使われるためである。ノードは同一性に種類を添えたものであり、同一性はノードより広く流れる。
//!
//! **Rustの項目は、Rustと同じく型の名前空間と値の名前空間に分ける。** Rustは型(構造体・列挙・トレイト)と値(関数)を別の名前空間に置き、
//! 同じモジュールに同じ名前の型と自由関数を書ける。1つの名前空間にまとめると、その2つが同じ識別子になって同一性の衝突に数えられ、全部の答えを弱める。
//! 種類そのものを同一性へ入れないのは変えない。型とトレイトは同じ型の名前空間に在り、抽出器が目的語の種類を推測で外した箇所を同一性の衝突として数え続けるためである。
//!
//! 1本の文字列へ連結しないのは、クレートだけで絞る問いと名前だけで絞る問いの両方が在り、連結すると問うたびに文字列を切り直すことになるためである。
//! 参照: `_doc/設計/設計オントロジー.md` 第6節。

/// 設計概念の名前が住む空間。Rustのソースに定義が在る項目を型と値の2つの名前空間に分け、実行時にだけ存在するドメインの概念と区別する。
/// 実行時のドメイン概念を区別するのは、それにはモジュールパスが無く、定義をたどれずモジュールパスが空になった
/// Rustの型と同じ形になるためである。空文字を「Rustの型ではない」という意味へ密輸しない。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum 設計概念の名前空間 {
    /// Rustのソースに定義が在る、型の名前空間の項目(構造体・列挙・トレイト)。モジュールパスは定義の位置を指す。
    Rustの型の名前空間,
    /// Rustのソースに定義が在る、値の名前空間の項目(関数)。モジュールパスは定義の位置を指す。
    Rustの値の名前空間,
    /// 実行時にだけ存在するドメインの概念。Rustの型であるとは限らず、モジュールパスは名前の空間として使う。
    実行時のドメイン概念,
}

/// 設計概念の同一性。名前空間と定義のモジュールパスと所有者の並びと名前の4つ組である。
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct 設計概念の識別子 {
    /// Rustの型の名前空間の項目か、値の名前空間の項目か、実行時のドメイン概念か。
    pub 名前空間: 設計概念の名前空間,
    /// `blitz_esca::旅行者` の形。`crates` の下に無いものと、定義をたどれなかったものは空である。
    pub モジュールパス: String,
    /// その名前を所有する型の並び。関連関数なら所有する型の名前が入り、無ければ空である。
    pub 所有者の並び: Vec<String>,
    /// 型引数を落とした先頭の識別子(`遷移成功結果<状態, イベント>` なら `遷移成功結果`)。フレーム型だけは座標系を含む(`変位<ワールド>`)。
    pub 名前: String,
}

impl 設計概念の識別子 {
    /// Rustのソースに定義が在る項目の識別子を組む。所有者の並びは空であり、名前空間は型の名前空間である。
    /// 処理のノードを組むときは、ノードと参照の組み立てが種類に合わせて値の名前空間へ据え直す。
    #[allow(non_snake_case)] // 日本語の識別子に含むASCIIの大文字はRustの命名規則の検査に掛かる。言語の名前をそのまま使う。
    pub fn Rustの項目として生成する(モジュールパス: &str, 名前: &str) -> Self {
        Self::名前空間を決めて生成する(設計概念の名前空間::Rustの型の名前空間, モジュールパス, 名前)
    }

    /// 実行時にだけ存在するドメインの概念の識別子を組む。名前の空間には、その概念を語る型が居るモジュールを渡してよく、空でもよい。
    pub fn 実行時のドメイン概念として生成する(名前の空間: &str, 名前: &str) -> Self {
        Self::名前空間を決めて生成する(設計概念の名前空間::実行時のドメイン概念, 名前の空間, 名前)
    }

    /// 所有者の並びを添えた識別子。`旅行者::更新する` と `世界::更新する` のように、名前だけでは同じになる別物を分けるために要る。
    pub fn 所有者を添える(self, 所有者の並び: Vec<String>) -> Self {
        Self { 所有者の並び, ..self }
    }

    // 名前空間をその種類が住むRustの名前空間へ据え直した同じ識別子。Rustの項目のノードを組む関数だけがこれを呼び、名前空間と種類の食い違うノードを組めないようにする。
    pub(super) fn 名前空間を種類に合わせて据える(self, 種類: super::Rustの項目の種類) -> Self {
        let 名前空間 = match 種類 {
            super::Rustの項目の種類::型 | super::Rustの項目の種類::トレイト => 設計概念の名前空間::Rustの型の名前空間,
            super::Rustの項目の種類::処理 => 設計概念の名前空間::Rustの値の名前空間,
        };
        Self { 名前空間, ..self }
    }

    fn 名前空間を決めて生成する(名前空間: 設計概念の名前空間, モジュールパス: &str, 名前: &str) -> Self {
        Self {
            名前空間,
            モジュールパス: モジュールパス.to_string(),
            所有者の並び: Vec::new(),
            名前: 名前.to_string(),
        }
    }

    /// 最上位のクレート名。モジュールパスが空なら空である。
    pub fn クレート名(&self) -> &str {
        self.モジュールパス.split("::").next().unwrap_or_default()
    }

    /// Rustの項目でありながら定義のモジュールパスが求まっていないか。抽出器がたどれなかった型のノードがこれである。
    /// 実行時のドメイン概念はモジュールパスが空でも定義をたどれなかったわけではないため、偽の未決定を出さないようこの問いで分ける。
    #[allow(non_snake_case)] // 日本語の識別子に含むASCIIの大文字はRustの命名規則の検査に掛かる。言語の名前をそのまま使う。
    pub fn Rustの項目でありながら定義をたどれていないか(&self) -> bool {
        self.名前空間 != 設計概念の名前空間::実行時のドメイン概念 && self.モジュールパス.is_empty()
    }

    /// 人が読む1行の表記。違反と反例の報告がこの表記を使う。モジュールパスと所有者の並びと名前を `::` で繋ぎ、空の欄は落とす。
    pub fn 表記(&self) -> String {
        let mut 表記の要素一覧 = Vec::new();
        if !self.モジュールパス.is_empty() {
            表記の要素一覧.push(self.モジュールパス.clone());
        }
        表記の要素一覧.extend(self.所有者の並び.iter().cloned());
        表記の要素一覧.push(self.名前.clone());
        表記の要素一覧.join("::")
    }
}
