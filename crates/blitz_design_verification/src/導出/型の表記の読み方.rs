//! 型の表記の読み方とは、型の表記の書かれた文字列から、その表記が名指す設計概念の名前を採る定義の式の側の知識のことである。依存を持たない純粋な関数だけを置く。
//! 受け取るのはソースに書かれた型の表記の書かれた文字列、返すのはその表記が名指す型か、設計概念ではないという答えか、読めないという答えである。
//!
//! この知識が宣言の側(抽出器)でなく定義の式の側に在るのは、包みの剥がし方とフレーム型の一覧が「フィールドに持つことが何を保持することか」の
//! 定義の一部だからである(Issue #193 の契約)。宣言の側は包みを剥がす前の書かれた文字列をそのまま運ぶ。
//!
//! 外側の包み(`Vec<T>`・`Option<T>`・`Box<T>`・`BTreeSet<T>`)を剥がして中身を採るのは、包みが設計上の関係を変えないためである。
//! `Arc<T>` を含めるのは、`M不変データ` の型が `M共有される不変データ` の型を共有して持つ形(設計オントロジー 2.5.3 の共通の法則3)であり、共有して持つことも中身の型を持つことであるためである。
//! `Arc` だけはパスの修飾を `std::sync::Arc` と `alloc::sync::Arc` に限る。同じ名前の別の型を標準の `Arc` と取り違えないためである。
//! `BTreeSet<T>` を含めるのは、要素の並びが決まる集合を持つことも要素の型を持つことであり、`Vec<T>` と同じく型引数が1つで中身の型をそのまま名指すためである(Issue #187 の作業G1。経路の開閉の状態が閉じている経路の集合を持つ)。
//! プリミティブを設計概念にしないのは、それが設計の概念ではなく数値と文字の表現だからである。
//! 値を持たない標準の型 `std::convert::Infallible` を設計概念にしないのは、失敗しない状態遷移が失敗の位置に置く型であり、名指す設計概念が無いためである(設計オントロジー第3節)。
//! 標準の `PhantomData<T>` は型の制約だけを運び、`T` の値を持たないため、修飾まで一致する名前と型引数が1つの名前である表記だけを設計概念から外す。
//! この3つが、黙って対象から外してよいと書き下せる条件である。値を持たない型はパスの修飾まで一致する書かれた文字列だけを受け取り、同じ名前の別の定義と取り違えない。
//! 剥がす包みでないジェネリクスのうち、座標系を型引数に取る `blitz_math` のフレーム型だけは、型引数を含む表記の全体を1つの型として採る。
//! 残る表記(配列・タプル・関数ポインタ・一覧に無いジェネリクス・パスの修飾が付いた表記)は、黙って読み飛ばさずに読めないと答える。
//! パスの修飾を読めないとするのは、修飾を落として名前だけで定義を探すと、同じ名前の別の定義へ当たりうるためである。

use super::型の表記を読めない理由の定義::型の表記を読めない理由;
use super::表記が名指す型の定義::{フレーム型, 先頭の識別子, 表記が名指す型};

/// 設計概念にしないプリミティブの型。数値と真偽と文字列であり、どれもドメインの概念を名乗らない。
const プリミティブ一覧: [&str; 11] = ["u8", "u32", "u64", "usize", "i32", "i64", "f32", "f64", "bool", "String", "str"];

/// 設計概念にしない、値を1つも持たない標準の型。パスの修飾まで一致する書かれた文字列だけを並べる。
const 値を持たない型一覧: [&str; 2] = ["std::convert::Infallible", "core::convert::Infallible"];

/// 外側から剥がす包み。剥がしても設計上の関係が変わらないものだけを並べる。
const 剥がす包み一覧: [&str; 5] = ["Vec", "Option", "Box", "BTreeSet", "Arc"];

/// `Arc` の包みとして受け取る書かれた文字列。修飾の無い名前と、標準の2つの修飾した表記である。
const 共有の包みの表記一覧: [&str; 3] = ["Arc", "std::sync::Arc", "alloc::sync::Arc"];

/// 型の表記を読んだ答え。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 型の表記の読み取り {
    /// 設計概念である型を名指せた。
    設計概念である(表記が名指す型),
    /// 設計の概念でないプリミティブであり、明示して対象から外す。
    プリミティブである,
    /// 設計概念の値を保持しない標準の型であり、名指す設計概念が無いため明示して対象から外す。
    値を持たない型である,
    /// 定義の式が読めない表記である。
    保証範囲の外(型の表記を読めない理由),
}

/// 型の表記から設計概念の名前を採る。
pub fn 型の表記を読む(表記: &str) -> 型の表記の読み取り {
    match 包みを剥がす(表記, 参照を落とす(表記)) {
        Err(理由) => 型の表記の読み取り::保証範囲の外(理由),
        Ok(芯) => match 芯.split_once('<') {
            None => 名前として読む(表記, 芯),
            Some(("std::marker::PhantomData" | "core::marker::PhantomData", 残り)) if 残り.strip_suffix('>').is_some_and(|型| !型.is_empty() && 先頭の識別子(型) == 型) => 型の表記の読み取り::値を持たない型である,
            Some((前, 残り)) => 総称の型として読む(表記, 前.trim(), 残り),
        },
    }
}

// `Vec<T>`・`Option<T>`・`Box<T>`・`BTreeSet<T>`・`Arc<T>` を、包みでなくなるまで剥がす。剥がす包みでないジェネリクスは芯としてそのまま返し、閉じない `<` は読めない。
fn 包みを剥がす<'a>(元の表記: &str, 表記: &'a str) -> Result<&'a str, 型の表記を読めない理由> {
    let mut 芯 = 表記;
    loop {
        let Some((前, 残り)) = 芯.split_once('<') else {
            return Ok(芯);
        };
        if !剥がす包みか(前) {
            return Ok(芯);
        }
        let Some((中身, _)) = 残り.rsplit_once('>') else {
            return Err(型の表記を読めない理由::型の表記がRustのパスでない { 表記: 元の表記.trim().to_string() });
        };
        芯 = 参照を落とす(中身);
    }
}

// 型引数の前の表記が剥がす包みか。最後の名前が一覧にあり、`Arc` なら書かれた文字列が標準の書かれた文字列のどれかである。
fn 剥がす包みか(前: &str) -> bool {
    let 最後の名前 = 前.rsplit("::").next().unwrap_or_default().trim();
    剥がす包み一覧.contains(&最後の名前) && (最後の名前 != "Arc" || 標準の共有の包みの表記か(前))
}

/// 書かれた文字列が標準の `Arc` の書かれた文字列(修飾の無い `Arc`・`std::sync::Arc`・`alloc::sync::Arc`)か。Rust はパスの区切りの前後に空白を許すため、比べる前に書かれた文字列の空白をすべて除く(`std :: sync :: Arc` も標準の書かれた文字列である)。
pub fn 標準の共有の包みの表記か(書かれた文字列: &str) -> bool {
    let 空白を除いた文字列: String = 書かれた文字列.chars().filter(|文字| !文字.is_whitespace()).collect();
    共有の包みの表記一覧.contains(&空白を除いた文字列.as_str())
}

// 包みを剥がした芯のうち型引数を持つものを、一覧に載ったフレーム型として読む。載っていない型、パスの修飾、読めない型引数は読めない。
fn 総称の型として読む(元の表記: &str, 前: &str, 残り: &str) -> 型の表記の読み取り {
    let 表記 = 元の表記.trim().to_string();
    let Some(型) = フレーム型::名前から探す(前.rsplit("::").next().unwrap_or_default().trim()) else {
        return 型の表記の読み取り::保証範囲の外(型の表記を読めない理由::型の表記が剥がす包みでないジェネリクスである { 表記 });
    };
    if 前.contains("::") {
        return 型の表記の読み取り::保証範囲の外(型の表記を読めない理由::型の表記にパスの修飾がある { 表記 });
    }
    let Some(型引数の並び) = 残り.trim_end().strip_suffix('>') else {
        return 型の表記の読み取り::保証範囲の外(型の表記を読めない理由::型の表記がRustのパスでない { 表記 });
    };
    match 表記が名指す型::フレーム型として読む(型, 型引数の並び) {
        Some(名指す型) => 型の表記の読み取り::設計概念である(名指す型),
        None => 型の表記の読み取り::保証範囲の外(型の表記を読めない理由::フレーム型の型引数が座標系の名前の並びでない { 表記 }),
    }
}

// 包みを剥がした芯を、設計概念の名前として読む。パスの修飾が付いた表記と、識別子として読めない表記は読めない。
fn 名前として読む(元の表記: &str, 芯: &str) -> 型の表記の読み取り {
    let 名前 = 芯.trim();
    if 値を持たない型一覧.contains(&名前) {
        return 型の表記の読み取り::値を持たない型である;
    }
    if 名前.contains("::") {
        return 型の表記の読み取り::保証範囲の外(型の表記を読めない理由::型の表記にパスの修飾がある { 表記: 元の表記.trim().to_string() });
    }
    if 名前.is_empty() || 先頭の識別子(名前) != 名前 {
        return 型の表記の読み取り::保証範囲の外(型の表記を読めない理由::型の表記がRustのパスでない { 表記: 元の表記.trim().to_string() });
    }
    if プリミティブ一覧.contains(&名前) {
        return 型の表記の読み取り::プリミティブである;
    }
    型の表記の読み取り::設計概念である(表記が名指す型::名前から生成する(名前))
}

// 先頭の参照と寿命と `mut` を落とす。落とせるものが無くなるまで繰り返す。
fn 参照を落とす(表記: &str) -> &str {
    let mut 残り = 表記.trim();
    loop {
        let 落とした = 残り.strip_prefix('&').unwrap_or(残り).trim_start();
        let 落とした = 寿命を落とす(落とした);
        let 落とした = 落とした.strip_prefix("mut ").unwrap_or(落とした).trim_start();
        if 落とした == 残り {
            return 残り;
        }
        残り = 落とした;
    }
}

// `&'a 型` の `'a ` を落とす。寿命の名前の後ろに空白が無ければ、寿命ではないものとして何も落とさない。
fn 寿命を落とす(表記: &str) -> &str {
    let Some(残り) = 表記.strip_prefix('\'') else {
        return 表記;
    };
    残り.split_once(char::is_whitespace).map_or(表記, |(_, 後ろ)| 後ろ.trim_start())
}
