//! 関数の署名の事実とは、`fn` の項目1件について、誰が持つか・受け手をどう受けるか・何を引数に取るか・何を返すかを、表記のまま並べたプリミティブな事実のことである(Issue #175 の第2段階)。
//!
//! **事実は設計の意味を持たない。** 引数と戻り値の表記は `Self` を所有者の表記へ置き換えただけの書かれた文字列のまま運び、どの型を名指すかは定義の式の署名の読み方が決める。
//! 定義の式はこの事実からプリミティブな関係(関連関数として持つ・引数に取る・返す)だけを導き、設計の関係(変換用の素材にする・生成する)を導かない。
//! 生の `fn f(a: A) -> B` から設計の関係を導くと、関数の引数と戻り値という言語の形がそのまま設計の意味になり、設計として説明可能かを問う力を失うためである
//! (`_doc/設計/設計オントロジー.md` 6.5節)。

use crate::{事実の出どころ, 設計概念, 設計概念への参照};

use super::プリミティブな事実の定義::型の表記;

/// 関数の項目1件の署名。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 関数の署名の事実 {
    /// その関数の節点。種類は処理であり、識別子は関数の役割の宣言が包んだ関数と同じ組み方で作る。
    pub 処理: 設計概念,
    /// その関数を誰が持つか。
    pub 所有者: 関数の所有者,
    /// 受け手(`self`)をどう受けるか。
    pub 受け手: 受け手の種類,
    /// 受け手を除いた引数の型の表記を、位置の順に並べた一覧。
    pub 引数の表記一覧: Vec<型の表記>,
    /// 戻り値の型の表記。`->` を書いていない関数では無しである。
    pub 戻り値の表記: Option<型の表記>,
    /// この1件がどのソースのどの行から出たか。`fn` の行を指す。
    pub 出どころ: 事実の出どころ,
}

/// 関数を持つもの。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 関数の所有者 {
    /// モジュールの直下の関数であり、所有者を持たない。
    自由関数,
    /// `impl 型 { }` か `impl トレイト for 型 { }` の本体の関数。その型の表記を持つ。
    型(型の表記),
    /// `trait 名 { }` の本体の関数。そのトレイトの節点への参照を持つ。
    トレイト(設計概念への参照),
}

/// 受け手の受け方。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 受け手の種類 {
    /// 受け手を持たない(関連関数か自由関数)。
    無し,
    /// `self`・`mut self` のように値で受ける。
    値,
    /// `&self` のように参照で受ける。
    参照,
    /// `&mut self` のように可変参照で受ける。
    可変参照,
}

impl 受け手の種類 {
    /// 人が読む語。計測の表示がこの語を使う。
    pub const fn 語(self) -> &'static str {
        match self {
            Self::無し => "受け手無し",
            Self::値 => "値",
            Self::参照 => "参照",
            Self::可変参照 => "可変参照",
        }
    }
}
