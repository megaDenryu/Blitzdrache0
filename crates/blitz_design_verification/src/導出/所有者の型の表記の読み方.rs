//! 所有者の型の表記の読み方とは、`impl 型 { }` と `impl トレイト for 型 { }` の対象の型の表記から、その関数を関連関数として持つ型を採る定義の式の側の知識のことである。
//! 依存を持たない純粋な関数だけを置く。受け取るのは実装の対象の型の表記、返すのは名指す型か、設計概念でないか、読めないという答えである。
//!
//! **包みを剥がさず、1つの表記から1つの型だけを名指す。** 関数を持つのは実装の対象の型そのものであり、`impl トレイト for Vec<Foo>` の関数を持つのは `Vec` であって `Foo` ではない。
//! フィールドの読み方は包みを剥がし、署名の読み方は組と `Result` から複数の型を名指すため、どちらで読んでも持ち主でない型を持ち主と取り違える。
//! 型引数は落として型の名前で名指す(`impl<T> 包み<T>` の関数を持つのは `包み`)。処理の識別子の所有者の名前も同じ名前であるためである。
//! 座標系を型引数に取るフレーム型だけは、フィールドの読み方と同じく座標系を含めた名前で名指す。組・配列・関数ポインタは1つの型を名指さないため読めない。

use super::型の表記の読み方::{参照を落とす, 名前として読む, 型の表記の読み取り, 総称の型として読む};
use super::表記が名指す型の定義::フレーム型;

/// 実装の対象の型の表記から、その実装の関数を関連関数として持つ型を採る。
pub fn 所有者の型の表記を読む(表記: &str) -> 型の表記の読み取り {
    let 芯 = 参照を落とす(表記).trim();
    match 芯.split_once('<') {
        Some((前, 残り)) if フレーム型::名前から探す(前.rsplit("::").next().unwrap_or_default().trim()).is_some() => 総称の型として読む(表記, 前.trim(), 残り),
        Some((前, _)) => 名前として読む(表記, 前),
        None => 名前として読む(表記, 芯),
    }
}
