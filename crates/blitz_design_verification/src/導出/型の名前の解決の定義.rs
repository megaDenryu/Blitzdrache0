//! 型の名前の解決とは、型の表記を書いた場所から見て、その名前の型かトレイトの定義がどのモジュールに在るかを答える口のことである。
//! トレイトを問うのは、関数の署名の `impl トレイト`・`dyn トレイト` が境界のトレイトを名指し、その節点をトレイトの定義の在り処で組むためである。
//!
//! **解決を事実の値でなく口にするのは、どの名前を解決するかを定義の式が決めるためである。** 包みを剥がして芯の名前を採るのは定義の式の知識であり、
//! 事実の側(抽出器)は剥がす前の書かれた文字列しか知らない。したがって抽出器が先回りして名前を解決しておくことはできず、定義の式の評価器が
//! 芯の名前を採った時点で、この口へ問う。解決そのもの(同じファイルの定義・`use` の取り込み・同名の定義の候補の選び方)はRustの名前解決であり、
//! このクレートは抽出器(`xtask`)を知らないため持たない。抽出器が、自分の構文解析器でこの口を実装する。
//! 口がトレイトであるのは、実装が抽出器のソース群と試験の表の2つに分かれ、評価器がどちらにも同じ問いを投げるためである。
//!
//! 修飾の無い名前も、`use` で標準ライブラリ(`std`・`core`・`alloc`)から取り込んだ名前(`use std::fmt::Display;` の後の `Display`)と、
//! 取り込まずに見えるプレリュードのトレイト(`Clone`・`Iterator` など)なら、修飾で `std::fmt::Display` と書いたときと同じく標準ライブラリの項目であると答える。
//! 書き方によって、同じ標準ライブラリの項目が関係を作らなかったり、モジュールパスの空の節点になったりしないためである。
//!
//! パスの修飾が付いた名前(`fmt::Result`・`crate::a::型`)は、修飾がどのモジュールを指すかを `use` の取り込みから決めてから、そのモジュールの定義を探す。
//! 修飾の頭が型の名前なら(`型::関連型`)、その名前は型の関連項目であり、どのモジュールの定義でもない。

use crate::{Rustの項目の種類, 事実の出どころ};

/// 修飾の無い名前を解決した答え。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 修飾の無い名前の解決 {
    /// 書いた位置から見える定義を探し当てた。
    定義がある {
        /// 定義を書いたモジュールのパスの表記(`blitz_game::移動`)。
        モジュールパス: String,
    },
    /// `use` で標準ライブラリから取り込んだ名前か、取り込まずに見えるプレリュードのトレイトである。設計概念でないため、関係を導かない。
    標準ライブラリの項目である,
    /// 書いた位置から見える定義をたどれなかった(適用範囲の外のクレートを含む)。
    定義をたどれない,
}

/// パスの修飾が付いた名前を解決した答え。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 修飾された名前の解決 {
    /// 修飾が標準ライブラリ(`std`・`core`・`alloc`)のモジュールを指す。設計概念でないため、関係を導かない。
    標準ライブラリの項目である,
    /// 修飾が指すモジュールから、その名前の定義を探し当てた。
    定義がある {
        /// 定義を書いたモジュールのパスの表記(`blitz_game::移動`)。
        モジュールパス: String,
    },
    /// 修飾が指すモジュールに、その名前の定義をたどれなかった(適用範囲の外のクレートを含む)。
    定義をたどれない,
    /// 修飾の頭が型の名前であり、名前はその型の関連項目(`Self::関連型`)である。定義の式はこの表記を読めない。
    型の関連項目である,
}

/// 型の表記を書いた場所から見た、型かトレイトの名前の定義の在り処を答える口。
pub trait 型の名前の解決 {
    /// 参照元から見た、修飾の無いその名前のその種類(型かトレイト)の定義の在り処。
    /// 定義の式は型の表記から処理を名指さないため、種類が処理の問いは来ない。
    fn 修飾の無い名前を解決する(&self, 名前: &str, 種類: Rustの項目の種類, 参照元: &事実の出どころ) -> 修飾の無い名前の解決;

    /// 参照元から見た、パスの修飾(`fmt`・`crate::a`)の付いた名前のその種類の定義の在り処。
    fn 修飾された名前を解決する(&self, 修飾: &str, 名前: &str, 種類: Rustの項目の種類, 参照元: &事実の出どころ) -> 修飾された名前の解決;
}
