//! 定義の式とは、設計の関係(消費する・生成する・参照する・識別する)とプリミティブの高さの関係(保持する)を、
//! プリミティブな事実の上の規則として値で並べたもののことである(Issue #193「定義の式」)。
//!
//! 規則は、頭の関係と、本体のプリミティブな原子の連言でできている。本体の事実の原子は事実1件を選んで概念の変数と型の表記を当て、
//! `表記が型を名指す` がその表記を定義の式の読み方で読んで型を当てる。頭は当たった主語と目的語の間に関係を1件置く。
//! 規則を関数の中の場合分けでなく値で持つのは、報告が「どの規則がどの事実から導いたか」を示せるようにするためと、
//! 型の表記を持つ事実を #175 が足したときに、事実の原子と規則を足せば関係を定義できるようにするためである。
//! 両端が節点の事実と分類と組み合わせる定義は、この形では書けない(`規則の本体の原子` の冒頭を見る)。
//!
//! 役割の定義の知識(型引数の位置ごとに何を消費し何を生成するか、`M遷移関数` が固定で受け取る `遷移パラメータ`)はここに在る。
//! `M遷移関数` の第1の型引数(状態)は現在の状態として消費され次の状態として生成されるため、2つの規則に現れる。
//! 第5の型引数(失敗)を生成するのは、`Err(遷移失敗結果<状態, 失敗>)` が運ぶ失敗の理由がその処理の取りうる明白な出力であるためであり、
//! 毎回は生成されないことは除外の理由にならない(`Mイベント` も毎回は生成されない)。
//! `遷移パラメータ` を固定の入力として持つのは、`遷移の関数ポインタ`(`crates/blitz_esca/src/ontology.rs`)の第4引数として役割の定義が固定しており、
//! 使用箇所の表記 `M遷移関数<状態, コマンド, 規則, イベント, 失敗>` には現れないためである。表記が無いことは、その入力が無いことを意味しない。

use super::役割::関数の役割;
use super::規則の本体の原子::{事実の原子, 本体の原子, 概念の変数};
use crate::{抽出元の構文, 設計関係の種類};

/// 規則の頭の関係。設計の高さの関係か、プリミティブの高さの保持するかを区別する。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 頭の関係 {
    /// 設計の関係を1件導く。
    設計関係(設計関係の種類),
    /// 保持する関係を1件導く。
    保持する,
}

/// 定義の式の規則1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 導出の規則 {
    /// 報告と導出の根拠に出す規則の名前。
    pub 名前: &'static str,
    /// 本体が成り立つときに導く関係。
    pub 頭: 頭の関係,
    /// 連言で結ぶ原子の並び。左から順に当てる。
    pub 本体: Vec<本体の原子>,
    /// 導いた関係の出どころに書く、表記が在った構文。
    pub 構文: 抽出元の構文,
}

/// 定義の式の全体。規則を当てる順に並べる。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 定義の式 {
    規則一覧: Vec<導出の規則>,
}

// 関数の役割の型引数の位置ごとの規則。名前・役割・位置・導く関係の種類の順である。
const 役割の型引数の規則表: [(&str, 関数の役割, usize, 設計関係の種類); 10] = [
    ("解釈関数は第1の型引数の入力を消費する", 関数の役割::M解釈関数, 0, 設計関係の種類::消費する),
    ("解釈関数は第2の型引数のコマンドを生成する", 関数の役割::M解釈関数, 1, 設計関係の種類::生成する),
    ("射影関数は第1の型引数の状態を消費する", 関数の役割::M射影関数, 0, 設計関係の種類::消費する),
    ("射影関数は第2の型引数の射影を生成する", 関数の役割::M射影関数, 1, 設計関係の種類::生成する),
    ("遷移関数は第1の型引数の状態を消費する", 関数の役割::M遷移関数, 0, 設計関係の種類::消費する),
    ("遷移関数は第2の型引数のコマンドを消費する", 関数の役割::M遷移関数, 1, 設計関係の種類::消費する),
    ("遷移関数は第3の型引数の規則を参照する", 関数の役割::M遷移関数, 2, 設計関係の種類::参照する),
    ("遷移関数は第4の型引数のイベントを生成する", 関数の役割::M遷移関数, 3, 設計関係の種類::生成する),
    ("遷移関数は第5の型引数の失敗を生成する", 関数の役割::M遷移関数, 4, 設計関係の種類::生成する),
    ("遷移関数は第1の型引数の状態を次の状態として生成する", 関数の役割::M遷移関数, 0, 設計関係の種類::生成する),
];

impl 定義の式 {
    /// 設計の関係4語と保持するの定義。関数の役割の規則・固定の入力の規則・識別子の規則・保持するの規則の順に当てる。
    pub fn 設計の関係と保持するの定義() -> Self {
        let 役割の型引数の規則 = 役割の型引数の規則表.into_iter().map(|(名前, 役割, 位置, 種類)| 導出の規則 {
            名前,
            頭: 頭の関係::設計関係(種類),
            本体: vec![
                本体の原子::事実(事実の原子::役割の型引数を持つ {
                    役割, 位置, 処理: 概念の変数::主語
                }),
                本体の原子::表記が型を名指す { 型: 概念の変数::目的語 },
            ],
            構文: 抽出元の構文::関数の役割の型引数,
        });
        let 残りの規則 = [
            導出の規則 {
                名前: "遷移関数は役割の定義が固定で受け取る遷移パラメータを消費する",
                頭: 頭の関係::設計関係(設計関係の種類::消費する),
                本体: vec![
                    本体の原子::事実(事実の原子::役割の定義が固定で受け取る {
                        役割: 関数の役割::M遷移関数,
                        型名: "遷移パラメータ",
                        処理: 概念の変数::主語,
                    }),
                    本体の原子::表記が型を名指す { 型: 概念の変数::目的語 },
                ],
                構文: 抽出元の構文::関数の役割が固定で持つ入力,
            },
            導出の規則 {
                名前: "識別子の関連型が名指す型はそのエンティティを識別する",
                頭: 頭の関係::設計関係(設計関係の種類::識別する),
                本体: vec![
                    本体の原子::事実(事実の原子::エンティティの識別子の関連型を持つ {
                        エンティティ: 概念の変数::目的語
                    }),
                    本体の原子::表記が型を名指す { 型: 概念の変数::主語 },
                ],
                構文: 抽出元の構文::エンティティの識別子の関連型,
            },
            導出の規則 {
                名前: "フィールドの型が名指す型を持ち主が保持する",
                頭: 頭の関係::保持する,
                本体: vec![本体の原子::事実(事実の原子::フィールドの型の表記を持つ { 持ち主: 概念の変数::主語 }), 本体の原子::表記が型を名指す { 型: 概念の変数::目的語 }],
                構文: 抽出元の構文::構造体のフィールド,
            },
        ];
        Self {
            規則一覧: 役割の型引数の規則.chain(残りの規則).collect(),
        }
    }

    /// 当てる順に並んだ規則。
    pub fn 規則一覧(&self) -> &[導出の規則] {
        &self.規則一覧
    }
}
