//! 定義の式の評価の試験。事実を直に組み、表で答える解決の口を渡して、どの事実からどの関係と欠けが導かれるかを固定する。
//! このファイルは試験が共有する段取りと、フィールドの型の表記から保持するを導く規則の試験を持ち、役割と識別子の規則の試験は子のモジュールが持つ。
//!
//! 実物のRustのソースから事実を読む工程は、抽出器の側の試験(`xtask/src/design_model/extract/` の試験)が固定する。
//! ここでは評価器の規則の当て方だけを見る。

#[path = "導出の試験/役割と識別子の規則の試験.rs"]
mod 役割と識別子の規則の試験;

use std::path::PathBuf;

use super::{フィールドの型の表記の事実, プリミティブな事実, 型の名前の解決, 型の表記, 定義の式, 導出の欠けの理由, 概念の変数};
use super::{束縛::束縛, 評価::評価の工程};
use crate::{事実の出どころ, 設計概念, 設計概念への参照};

const 置き場: &str = "blitz_esca::traveler";

// 名前の一覧に載った型だけを `blitz_esca::traveler` に在ると答える解決の口。
struct 表で答える解決(&'static [&'static str]);

impl 型の名前の解決 for 表で答える解決 {
    fn 定義のモジュールパスを求める(&self, 型名: &str, _参照元: &事実の出どころ) -> Option<String> {
        self.0.contains(&型名).then(|| 置き場.to_string())
    }
}

impl 表で答える解決 {
    // この表を解決の口にして事実を評価し、導いた関係の表記と欠けの理由を返す。
    fn 評価して表記と欠けを返す(&self, 事実: &プリミティブな事実) -> (Vec<String>, Vec<導出の欠けの理由>) {
        let 結果 = 定義の式::設計の関係と保持するの定義().評価する(事実, self);
        let 表記一覧 = 結果.設計関係一覧.iter().map(|関係| 関係.表記()).chain(結果.保持する関係一覧.iter().map(|関係| 関係.表記())).collect();
        (表記一覧, 結果.欠け一覧.into_iter().map(|欠け| 欠け.理由).collect())
    }
}

fn 出どころ(行番号: usize) -> 事実の出どころ {
    事実の出どころ {
        パス: PathBuf::from("crates/blitz_esca/src/導出の試験の事実.rs"),
        行番号,
    }
}

fn 型(名前: &str) -> 設計概念への参照 {
    設計概念への参照::型として生成する(置き場, 名前)
}

fn フィールド(持ち主: &str, 綴り: &str, 型引数名一覧: &[&str], 行番号: usize) -> フィールドの型の表記の事実 {
    let 型引数名一覧 = 型引数名一覧.iter().map(|名前| (*名前).to_string()).collect();
    フィールドの型の表記の事実 {
        持ち主: 型(持ち主),
        表記: 型の表記::生成する(綴り, 型引数名一覧),
        出どころ: 出どころ(行番号),
    }
}

#[test]
fn フィールドの型は包みを剥がして保持する関係になり型引数とプリミティブは関係にならない() {
    let 事実 = プリミティブな事実 {
        フィールドの型の表記一覧: vec![フィールド("旅程", "Vec<旅行者の出来事>", &[], 2), フィールド("包み", "状態", &["状態"], 3), フィールド("旅程", "u32", &[], 4)],
        ..プリミティブな事実::default()
    };
    let (表記一覧, 欠け一覧) = 表で答える解決(&["旅行者の出来事"]).評価して表記と欠けを返す(&事実);
    assert_eq!(表記一覧, vec![format!("{置き場}::旅程 保持する {置き場}::旅行者の出来事")]);
    assert_eq!(欠け一覧, vec![導出の欠けの理由::型引数である { 型引数名: "状態".to_string() }]);
}

#[test]
fn 定義をたどれない型は節点を落とさずモジュールパスを空にして欠けを1件出す() {
    let 事実 = プリミティブな事実 {
        フィールドの型の表記一覧: vec![フィールド("旅程", "未知の型", &[], 2)],
        ..プリミティブな事実::default()
    };
    let 結果 = 定義の式::設計の関係と保持するの定義().評価する(&事実, &表で答える解決(&[]));
    assert_eq!(結果.保持する関係一覧[0].表記(), format!("{置き場}::旅程 保持する 未知の型"));
    assert!(結果.端点の概念一覧.contains(&設計概念::型として生成する("", "未知の型")));
    assert_eq!(結果.欠け一覧[0].理由, 導出の欠けの理由::定義のモジュールパスを解決できなかった { 型名: "未知の型".to_string() });
}

#[test]
#[should_panic(expected = "既に当たっている変数")]
fn 表記が型を名指す原子が当たっている変数へ当てようとしたら束縛を黙って落とさず止める() {
    let 事実 = プリミティブな事実::default();
    let 解決 = 表で答える解決(&["旅行者の出来事"]);
    let 工程 = 評価の工程 { 事実: &事実, 解決: &解決 };
    let 表記 = 型の表記::型引数の無い場所で生成する("旅行者の出来事");
    let Some(主語を当てた束縛) = 束縛::空().事実から当てる(概念の変数::主語, 型("旅程"), 表記, &出どころ(2)) else {
        panic!("何も当てていない束縛へ事実から当てられなかった: 試験の段取りが誤っている");
    };
    工程.名指す型を当てる(&主語を当てた束縛, 概念の変数::主語);
}
