const 置き場: &str = "blitz_esca::traveler";

// 名前の一覧に載った型だけを `blitz_esca::traveler` に在ると答え、修飾の無い `Display` を標準ライブラリの項目と答える定義の探索の口。
struct 表で答える定義の探索(&'static [&'static str]);

impl 型の名前の定義の探索 for 表で答える定義の探索 {
    fn 修飾の無い名前の定義を探す(&self, 型名: &str, _種類: crate::Rustの項目の種類, _参照元: &事実の出どころ) -> 修飾の無い名前の定義を探した結果 {
        match 型名 {
            _ if self.0.contains(&型名) => 修飾の無い名前の定義を探した結果::定義がある { モジュールパス: 置き場.to_string() },
            "Display" => 修飾の無い名前の定義を探した結果::標準ライブラリの項目である,
            _ => 修飾の無い名前の定義を探した結果::定義をたどれない,
        }
    }

    // 修飾が `std` で始まれば標準ライブラリ、`Self` なら型の関連項目、それ以外は表に載った名前だけを `blitz_esca::traveler` に在ると答える。
    fn 修飾された名前の定義を探す(&self, 修飾: &str, 名前: &str, _種類: crate::Rustの項目の種類, _参照元: &事実の出どころ) -> 修飾された名前の定義を探した結果 {
        match 修飾 {
            "Self" => 修飾された名前の定義を探した結果::型の関連項目である,
            _ if 修飾.starts_with("std") => 修飾された名前の定義を探した結果::標準ライブラリの項目である,
            _ if self.0.contains(&名前) => 修飾された名前の定義を探した結果::定義がある { モジュールパス: 置き場.to_string() },
            _ => 修飾された名前の定義を探した結果::定義をたどれない,
        }
    }
}

impl 表で答える定義の探索 {
    // この表を定義の探索の口にして事実を評価し、導いた関係の表記と欠けの理由を返す。
    fn 評価して表記と欠けを返す(&self, 事実: &プリミティブな事実) -> (Vec<String>, Vec<導出の欠けの理由>) {
        let 結果 = 定義の式::設計の関係とプリミティブな関係の定義().評価する(事実, &分類の事実::無い(), self);
        let 表記一覧 = 結果.設計関係一覧.iter().map(|関係| 関係.表記()).chain(結果.プリミティブな関係一覧.iter().map(|関係| 関係.表記())).collect();
        (表記一覧, 結果.欠け一覧.into_iter().map(|欠け| 欠け.理由).collect())
    }
}

fn 出どころ(行番号: usize) -> 事実の出どころ {
    事実の出どころ {
        パス: PathBuf::from("crates/blitz_esca/src/導出の試験の事実.rs"),
        行番号,
    }
}

fn 型(名前: &str) -> 設計概念への参照 {
    設計概念への参照::型として生成する(置き場, 名前)
}

fn フィールド(持ち主: &str, 書かれた文字列: &str, 型引数名一覧: &[&str], 行番号: usize) -> フィールドの型の表記の事実 {
    let 型引数名一覧 = 型引数名一覧.iter().map(|名前| (*名前).to_string()).collect();
    フィールドの型の表記の事実 {
        持ち主: 型(持ち主),
        表記: 型の表記::生成する(書かれた文字列, 型引数名一覧),
        出どころ: 出どころ(行番号),
    }
}

#[test]
fn フィールドの型は包みを剥がして保持する関係になり型引数とプリミティブは関係にならない() {
    let 事実 = プリミティブな事実 {
        フィールドの型の表記一覧: vec![フィールド("旅程", "Vec<旅行者の出来事>", &[], 2), フィールド("包み", "状態", &["状態"], 3), フィールド("旅程", "u32", &[], 4)],
        ..プリミティブな事実::default()
    };
    let (表記一覧, 欠け一覧) = 表で答える定義の探索(&["旅行者の出来事"]).評価して表記と欠けを返す(&事実);
    assert_eq!(表記一覧, vec![format!("{置き場}::旅程 保持する {置き場}::旅行者の出来事")]);
    assert_eq!(欠け一覧, vec![導出の欠けの理由::型引数である { 型引数名: "状態".to_string() }]);
}

#[test]
fn 共有される不変データを指すarcのフィールドは中身の型を保持する関係になり欠けを出さない() {
    let 事実 = プリミティブな事実 {
        フィールドの型の表記一覧: vec![フィールド("開閉の規則", "Arc<地図>", &[], 2), フィールド("空間制約", "std::sync::Arc<地図>", &[], 3)],
        ..プリミティブな事実::default()
    };
    let (表記一覧, 欠け一覧) = 表で答える定義の探索(&["地図"]).評価して表記と欠けを返す(&事実);
    assert_eq!(表記一覧, vec![format!("{置き場}::開閉の規則 保持する {置き場}::地図"), format!("{置き場}::空間制約 保持する {置き場}::地図")]);
    assert!(欠け一覧.is_empty(), "{欠け一覧:?}");
}

#[test]
fn 定義をたどれない型は節点を落とさずモジュールパスを空にして欠けを1件出す() {
    let 事実 = プリミティブな事実 {
        フィールドの型の表記一覧: vec![フィールド("旅程", "未知の型", &[], 2)],
        ..プリミティブな事実::default()
    };
    let 結果 = 定義の式::設計の関係とプリミティブな関係の定義().評価する(&事実, &分類の事実::無い(), &表で答える定義の探索(&[]));
    assert_eq!(結果.プリミティブな関係一覧[0].表記(), format!("{置き場}::旅程 保持する 未知の型"));
    assert!(結果.端点の概念一覧.contains(&設計概念::型として生成する("", "未知の型")));
    let 期待 = 導出の欠けの理由::定義のモジュールパスを求められなかった {
        型名: "未知の型".to_string(),
        変数の位置: 名指せなかった変数の位置::頭の端点,
    };
    assert_eq!(結果.欠け一覧[0].理由, 期待);
}
