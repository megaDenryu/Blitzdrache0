//! 関数の役割とは、関数へ設計上の役割を宣言する型(`M射影関数`・`M解釈関数`・`M遷移関数`)の区別のことである。
//!
//! このクレートが持つのは、役割の名前と、役割が取る型引数の数だけである。この2つは関数の役割の宣言という事実の形を決める。
//! 型引数の位置ごとにどの設計の関係を出すかは役割の定義の知識であり、`定義の式` の規則が持つ。
//! 役割の型を定義するモジュールの在り処は抽出器が知ることであり、このクレートは持たない。
//! 参照: `crates/blitz_design/src/function_role.rs`・`crates/blitz_esca/src/ontology.rs`。

/// 関数の設計上の役割。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum 関数の役割 {
    /// 入力を解釈してコマンドを作る関数の役割。
    M解釈関数,
    /// 状態を別の値へ写す関数の役割。
    M射影関数,
    /// 状態とコマンドと規則から次の状態と出来事を作る関数の役割。
    M遷移関数,
}

impl 関数の役割 {
    /// 3つの役割の全件。
    pub const fn 全部の一覧() -> [Self; 3] {
        [Self::M解釈関数, Self::M射影関数, Self::M遷移関数]
    }

    /// 役割の型の名前。ソースの綴りと同じである。
    pub const fn 名前(self) -> &'static str {
        match self {
            Self::M解釈関数 => "M解釈関数",
            Self::M射影関数 => "M射影関数",
            Self::M遷移関数 => "M遷移関数",
        }
    }

    /// その役割が取る型引数の数。
    pub const fn 型引数の数(self) -> usize {
        match self {
            Self::M解釈関数 | Self::M射影関数 => 2,
            Self::M遷移関数 => 5,
        }
    }
}
