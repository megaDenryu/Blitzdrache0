//! 命令の組を通した変換用の素材にする規則とは、「`M命令の組` が保持する `Mコマンド` は、その組を受け取った処理の変換用の素材になる」を、コマンドの位置を持つ遷移の役割ごとに1本ずつ書いた定義の式の規則のことである(2026-09-28 のオーナー裁定)。
//!
//! 本体は6つの原子の連言である。役割の宣言のコマンドの位置の表記から組を名指し(経由する概念)、その組が `M命令の組` を名乗り、組のフィールドの表記から型を名指し(目的語)、
//! その型が `Mコマンド` を名乗るときに、処理がその型を変換用の素材にすると導く。組そのものを変換用の素材にすることは位置の規則(`役割の型引数の規則表`)が別に導く。
//! 付いているマーカーを本体に書くのは、組でない値(コマンドの列挙が選択肢に持つ値オブジェクトなど)のフィールドから変換用の素材にするを導かないためと、組がコマンドでない値を持つ誤りを変換用の素材にするへ化けさせないためである。
//! 導いた関係の出どころはフィールドの行(抽出元の構文は構造体のフィールド)であり、導出の根拠は役割の宣言とフィールドの2つの宣言を並べる。
//! 同じコマンドの位置の表記を位置の規則とこの規則の2つが読むため、読めない表記の欠けは2件になる(`評価` の冒頭が書く重ねた数え方と同じである)。

use super::定義の式の規則一覧::{導出の規則, 頭の関係};
use super::規則の本体の原子::{宣言の原子, 本体の原子, 概念の変数};
use super::関数の役割の定義::関数の役割;
use crate::{抽出元の構文, 関数の引数と戻り値の役目};

// コマンドの位置を持つ遷移の役割と、コマンドの型引数の位置(0始まり)と、規則の名前。
const コマンドの位置の表: [(&str, 関数の役割, usize); 3] = [
    ("遷移関数は第2の型引数で受け取る命令の組が保持するコマンドを変換用の素材にする", 関数の役割::M遷移関数, 1),
    (
        "遷移が受け取る命令で決まる遷移関数は第2の型引数で受け取る命令の組が保持するコマンドを変換用の素材にする",
        関数の役割::M遷移が受け取る命令で決まる遷移関数,
        1,
    ),
    ("問い合わせを伴う遷移関数は第2の型引数で受け取る命令の組が保持するコマンドを変換用の素材にする", 関数の役割::M問い合わせを伴う遷移関数, 1),
];

/// 命令の組を通した変換用の素材にする規則を、コマンドの位置を持つ役割ごとに1本ずつ組む。
pub(super) fn 命令の組を通した変換用の素材にする規則一覧() -> impl Iterator<Item = 導出の規則> {
    コマンドの位置の表.into_iter().map(|(名前, 役割, 位置)| 導出の規則 {
        名前,
        頭: 頭の関係::設計関係(関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す()),
        本体: vec![
            本体の原子::宣言の原子(宣言の原子::役割の型引数を持つ {
                役割, 位置, 処理: 概念の変数::主語
            }),
            本体の原子::表記が型を名指す { 型: 概念の変数::経由する概念 },
            本体の原子::マーカーが付いている {
                変数: 概念の変数::経由する概念,
                マーカー名: "M命令の組",
            },
            本体の原子::宣言の原子(宣言の原子::フィールドの型の表記を持つ {
                持ち主: 概念の変数::経由する概念
            }),
            本体の原子::表記が型を名指す { 型: 概念の変数::目的語 },
            本体の原子::マーカーが付いている {
                変数: 概念の変数::目的語,
                マーカー名: "Mコマンド",
            },
        ],
        構文: 抽出元の構文::構造体のフィールド,
    })
}
