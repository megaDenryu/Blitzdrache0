//! 関数の署名の規則のうち、そのまま返すが値そのものと成分と値を1つだけ持つ包みの中身だけを数えることと、修飾の無い名前とパスの修飾が付いた名前を解決の口の答えに従って
//! 節点か欠けにすることを固定する試験。事実の組み方は親の試験の関数を使う。

use super::super::super::{型の表記, 定義の式, 導出の欠けの理由, 関数の所有者};
use super::super::{置き場, 表で答える解決};
use super::{事実, 署名};
use crate::{プリミティブな関係の種類, 分類の事実};

// 反証: そのまま返すが包みとトレイトの中まで読むと、候補を並べる関数と次の値を順に渡す関数まで、状態の値そのものを返す関数に数える。
#[test]
fn そのまま返すは値そのものと成分と値を1つだけ持つ包みの中身だけを数える() {
    let 戻り値一覧 = ["Vec<居場所>", "Option<居場所>", "impl Iterator<Item = 居場所>", "Box<居場所>", "(居場所, u8)"];
    let 署名一覧 = 戻り値一覧.iter().enumerate().map(|(番号, 戻り値)| 署名(&format!("関数{番号}"), 関数の所有者::自由関数, &[], Some(戻り値))).collect();
    let 結果 = 定義の式::設計の関係とプリミティブな関係の定義().評価する(&事実(署名一覧), &分類の事実::無い(), &表で答える解決(&["居場所"]));
    let そのまま返す関数一覧: Vec<String> = 結果
        .プリミティブな関係一覧
        .iter()
        .filter(|関係| 関係.種類 == プリミティブな関係の種類::そのまま返す)
        .map(|関係| 関係.主語.識別子().名前.clone())
        .collect();
    assert_eq!(そのまま返す関数一覧, vec!["関数3".to_string(), "関数4".to_string()]);
    let 返す関数の数 = 結果.プリミティブな関係一覧.iter().filter(|関係| 関係.種類 == プリミティブな関係の種類::返す && 関係.目的語.識別子().名前 == "居場所").count();
    assert_eq!(返す関数の数, 5, "返すは包みとトレイトの中まで数える: {:?}", 結果.プリミティブな関係一覧);
}

// 反証: 修飾の無い名前の口の答えを定義の在り処の有無だけで読むと、標準ライブラリから取り込んだ `Display` がモジュールパスの空の節点と欠けになる。
#[test]
fn 口が標準ライブラリの項目と答えた修飾の無い名前は関係も欠けも作らない() {
    let 総称 = 署名("見せる", 関数の所有者::自由関数, &["&dyn Display"], Some("impl Display"));
    let 結果 = 定義の式::設計の関係とプリミティブな関係の定義().評価する(&事実(vec![総称]), &分類の事実::無い(), &表で答える解決(&[]));
    assert!(結果.プリミティブな関係一覧.is_empty(), "{:?}", 結果.プリミティブな関係一覧);
    assert!(結果.欠け一覧.is_empty(), "{:?}", 結果.欠け一覧);
}

// 反証: パスの修飾が付いた名前を口へ問わずに読めない表記とすると、`use` で取り込んだモジュールを通して書いた型が関係を失う。
#[test]
fn 修飾された名前は口の答えに従って節点か欠けになる() {
    let mut 総称 = 署名("使う", 関数の所有者::自由関数, &["a::居場所", "Self::関連型", "外::無い型"], None);
    総称.引数の表記一覧.push(型の表記::生成する("T::関連型", vec!["T".to_string()]));
    let 結果 = 定義の式::設計の関係とプリミティブな関係の定義().評価する(&事実(vec![総称]), &分類の事実::無い(), &表で答える解決(&["居場所"]));
    let 表記一覧: Vec<String> = 結果.プリミティブな関係一覧.iter().map(|関係| 関係.表記()).collect();
    assert_eq!(表記一覧, vec![format!("{置き場}::使う 引数に取る {置き場}::居場所"), format!("{置き場}::使う 引数に取る 無い型")]);
    let 理由一覧: Vec<&導出の欠けの理由> = 結果.欠け一覧.iter().map(|欠け| &欠け.理由).collect();
    assert!(
        matches!(
            理由一覧.as_slice(),
            [
                導出の欠けの理由::関数の署名の型の表記を読めない(_),
                導出の欠けの理由::定義のモジュールパスを解決できなかった { .. },
                導出の欠けの理由::関数の署名の型の表記を読めない(_)
            ]
        ),
        "{理由一覧:?}"
    );
}
