//! 関数の署名の規則の試験。署名の事実からプリミティブな関係(関連関数として持つ・受け手に取る・引数に取る・返す)が導かれ、設計の関係は導かれないことと、
//! 読めない表記と型引数が関数の署名の答えを弱める欠けになることを固定する。

use super::super::{プリミティブな事実, 受け手の種類, 型の表記, 定義の式, 導出の欠けの理由, 落とした事実の種類, 関数の所有者, 関数の署名の事実, 頭の関係};
use super::{出どころ, 置き場, 表で答える解決};
use crate::{プリミティブな関係の種類, 分類の事実, 欠落が弱める答え, 設計概念, 設計概念への参照};

// 名前の関数の署名の事実を1件組む。引数と戻り値の表記は、書いた場所で有効な型引数を持たない。
fn 署名(名前: &str, 所有者: 関数の所有者, 引数一覧: &[&str], 戻り値: Option<&str>) -> 関数の署名の事実 {
    関数の署名の事実 {
        処理: 設計概念::処理として生成する(置き場, 名前),
        所有者,
        受け手: 受け手の種類::参照,
        引数の表記一覧: 引数一覧.iter().map(|書かれた文字列| 型の表記::型引数の無い場所で生成する(書かれた文字列)).collect(),
        戻り値の表記: 戻り値.map(型の表記::型引数の無い場所で生成する),
        出どころ: 出どころ(7),
    }
}

fn 事実(署名一覧: Vec<関数の署名の事実>) -> プリミティブな事実 {
    プリミティブな事実 {
        関数の署名一覧: 署名一覧,
        ..プリミティブな事実::default()
    }
}

#[test]
fn 型の所有者と引数と戻り値からプリミティブな関係だけを導き設計の関係を導かない() {
    let 所有者 = 関数の所有者::型(型の表記::型引数の無い場所で生成する("旅行者の居場所"));
    let 事実 = 事実(vec![署名("歩く", 所有者, &["&旅行者の意図", "u32"], Some("Result<旅行者の居場所, 歩行の失敗>"))]);
    let 結果 = 定義の式::設計の関係とプリミティブな関係の定義().評価する(&事実, &分類の事実::無い(), &表で答える解決(&["旅行者の居場所", "旅行者の意図", "歩行の失敗"]));
    assert!(結果.設計関係一覧.is_empty(), "関数の署名から設計の関係を導いた: {:?}", 結果.設計関係一覧);
    let 表記一覧: Vec<String> = 結果.プリミティブな関係一覧.iter().map(|関係| 関係.表記()).collect();
    assert_eq!(
        表記一覧,
        vec![
            format!("{置き場}::旅行者の居場所 関連関数として持つ {置き場}::歩く"),
            format!("{置き場}::歩く 受け手に取る {置き場}::旅行者の居場所"),
            format!("{置き場}::歩く 引数に取る {置き場}::旅行者の意図"),
            format!("{置き場}::歩く 返す {置き場}::旅行者の居場所"),
            format!("{置き場}::歩く 返す {置き場}::歩行の失敗"),
        ]
    );
    assert!(結果.欠け一覧.is_empty(), "{:?}", 結果.欠け一覧);
}

#[test]
fn トレイトの所有者はそのトレイトの節点が関数を関連関数として持ち受け手に取られる() {
    let トレイト = 設計概念への参照::トレイトとして生成する(置き場, "世界の形");
    let 事実 = 事実(vec![署名("尋ねる", 関数の所有者::トレイト(トレイト), &[], None)]);
    let 結果 = 定義の式::設計の関係とプリミティブな関係の定義().評価する(&事実, &分類の事実::無い(), &表で答える解決(&[]));
    let 表記一覧: Vec<String> = 結果.プリミティブな関係一覧.iter().map(|関係| 関係.表記()).collect();
    assert_eq!(表記一覧, vec![format!("{置き場}::世界の形 関連関数として持つ {置き場}::尋ねる"), format!("{置き場}::尋ねる 受け手に取る {置き場}::世界の形")]);
    assert!(結果.端点の概念一覧.iter().any(|概念| 概念.参照を貸す() == &設計概念への参照::トレイトとして生成する(置き場, "世界の形")));
}

#[test]
fn 読めない表記と型引数は関数の署名の欠けになりその規則の頭を運ぶ() {
    let mut 総称 = 署名("合わせる", 関数の所有者::自由関数, &[], None);
    総称.引数の表記一覧 = vec![型の表記::生成する("T", vec!["T".to_string()]), 型の表記::型引数の無い場所で生成する("fn(u8) -> u8")];
    let 結果 = 定義の式::設計の関係とプリミティブな関係の定義().評価する(&事実(vec![総称]), &分類の事実::無い(), &表で答える解決(&[]));
    assert!(結果.プリミティブな関係一覧.is_empty(), "{:?}", 結果.プリミティブな関係一覧);
    let 理由一覧: Vec<&導出の欠けの理由> = 結果.欠け一覧.iter().map(|欠け| &欠け.理由).collect();
    assert!(matches!(理由一覧[0], 導出の欠けの理由::関数の署名の型引数である { 型引数名 } if 型引数名 == "T"), "{理由一覧:?}");
    assert!(matches!(理由一覧[1], 導出の欠けの理由::関数の署名の型の表記を読めない(_)), "{理由一覧:?}");
    assert!(結果.欠け一覧.iter().all(|欠け| 欠け.導けなかった関係 == 頭の関係::プリミティブな関係(プリミティブな関係の種類::引数に取る)));
}

#[test]
fn 関数の署名を落とすと関数の署名が語る4つの答えだけを弱める() {
    let 答え一覧 = 定義の式::設計の関係とプリミティブな関係の定義().落とした事実が弱める答え一覧(落とした事実の種類::関数の署名);
    let 期待 = [
        プリミティブな関係の種類::関連関数として持つ,
        プリミティブな関係の種類::受け手に取る,
        プリミティブな関係の種類::引数に取る,
        プリミティブな関係の種類::返す,
    ]
    .map(欠落が弱める答え::プリミティブな関係);
    assert_eq!(答え一覧, 期待.to_vec());
}
