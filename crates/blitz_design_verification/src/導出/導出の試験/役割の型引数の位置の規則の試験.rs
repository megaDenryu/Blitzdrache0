//! 関数の役割の宣言の型引数の位置ごとに、どの設計の関係を導くかの規則の試験。段取りは親の `導出の試験` が持つ。
//! 役割ごとに1つの試験を置き、位置の規則が1本でも欠けるか、位置が入れ替わるか、関係を導かない位置から関係を導くと落ちる。
//! 問い合わせを伴う3つの役割の問い合わせ先と失敗の位置は、探索の表に載せない名前を置く。規則がその位置を読めば、関係か欠けが現れて落ちる。

use super::super::{プリミティブな宣言, 型の表記, 定義の式, 関数の役割, 関数の役割の宣言};
use super::{出どころ, 置き場, 表で答える定義の探索};
use crate::{設計概念ノード, 設計解釈マーカーの宣言の一覧};

// 関係を導かない位置へ置く名前。探索の表に載せないため、規則が読めば定義をたどれない欠けになる。
const 読まない位置の名前一覧: [&str; 2] = ["問い合わせ先", "失敗"];

// その役割で名前の一覧を型引数に持つ宣言1件を評価し、導いた関係を並べ替えた「処理 関係 目的語」の表記の一覧で返す。欠けが出たら試験を止める。
fn 宣言から導いた関係の表記一覧(役割: 関数の役割, 名前一覧: &[&'static str]) -> Vec<String> {
    let 宣言 = 関数の役割の宣言 {
        処理: 設計概念ノード::処理として生成する(置き場, "処理"),
        役割,
        型引数の表記一覧: 名前一覧.iter().map(|名前| 型の表記::型引数の無い場所で生成する(名前)).collect(),
        出どころ: 出どころ(9),
    };
    let プリミティブな宣言 = プリミティブな宣言 {
        関数の役割の宣言一覧: vec![宣言],
        ..プリミティブな宣言::default()
    };
    let 探索の表: Vec<&'static str> = 名前一覧.iter().copied().filter(|名前| !読まない位置の名前一覧.contains(名前)).collect();
    let 結果 = 定義の式::設計の関係とプリミティブな関係の定義().評価する(&プリミティブな宣言, &設計解釈マーカーの宣言の一覧::無い(), &表で答える定義の探索(探索の表.leak()));
    assert!(結果.欠け一覧.is_empty(), "{}の宣言から欠けが出た: {:?}", 役割.名前(), 結果.欠け一覧);
    let mut 表記一覧: Vec<String> = 結果.設計関係一覧.iter().map(|関係| 関係.表記().replace(&format!("{置き場}::"), "")).collect();
    表記一覧.sort();
    表記一覧
}

// 「処理」を主語にした期待の表記の一覧を並べ替えて返す。
fn 期待の表記一覧(残り一覧: &[&str]) -> Vec<String> {
    let mut 期待: Vec<String> = 残り一覧.iter().map(|残り| format!("処理 {残り}")).collect();
    期待.sort();
    期待
}

#[test]
fn 状態遷移関数の宣言は6つの型引数の位置ごとの関係を導く() {
    let 表記一覧 = 宣言から導いた関係の表記一覧(関数の役割::M状態遷移関数, &["状態", "コマンド", "規則", "パラメータ", "イベント", "失敗の理由"]);
    let 期待 = 期待の表記一覧(&[
        "変換用の素材にする 状態",
        "生成する 状態",
        "変換用の素材にする コマンド",
        "参照する 規則",
        "変換用の素材にする パラメータ",
        "生成する イベント",
        "生成する 失敗の理由",
    ]);
    assert_eq!(表記一覧, 期待);
}

#[test]
fn 状態遷移関数の状態遷移パラメータを変換用の素材にする関係は第4の型引数の規則を根拠に持つ() {
    let 宣言 = 関数の役割の宣言 {
        処理: 設計概念ノード::処理として生成する(置き場, "処理"),
        役割: 関数の役割::M状態遷移関数,
        型引数の表記一覧: ["状態", "コマンド", "規則", "パラメータ", "イベント", "失敗の理由"].map(型の表記::型引数の無い場所で生成する).to_vec(),
        出どころ: 出どころ(9),
    };
    let プリミティブな宣言 = プリミティブな宣言 {
        関数の役割の宣言一覧: vec![宣言],
        ..プリミティブな宣言::default()
    };
    let 結果 = 定義の式::設計の関係とプリミティブな関係の定義().評価する(&プリミティブな宣言, &設計解釈マーカーの宣言の一覧::無い(), &表で答える定義の探索(&["パラメータ"]));
    let 根拠 = 結果
        .設計関係一覧
        .iter()
        .find(|関係| 関係.目的語.識別子().名前() == "パラメータ")
        .map(|関係| (関係.根拠.規則の名前, 関係.根拠.使った宣言の出どころ一覧.clone()));
    assert_eq!(根拠, Some(("状態遷移関数は第4の型引数の状態遷移パラメータを変換用の素材にする", vec![出どころ(9)])));
}

