//! 欠けが弱める答えの試験。導出の欠けがそれを本体に持つ規則の頭の関係を運ぶことと、
//! 読めなかった事実の種類から弱める答えを規則の本体で求めることを固定する。

use super::super::{プリミティブな事実, 定義の式, 導出の欠けの理由, 落とした事実の種類, 頭の関係};
use super::{フィールド, 表で答える定義の探索};
use crate::{プリミティブな関係の種類, 分類の事実, 欠落が弱める答え, 設計関係の結び付き方, 関数の引数と戻り値の役目};

#[test]
fn 保持するの規則の本体で読めなかった欠けは保持するの頭を運ぶ() {
    let 事実 = プリミティブな事実 {
        フィールドの型の表記一覧: vec![フィールド("包み", "状態", &["状態"], 3)],
        ..プリミティブな事実::default()
    };
    let 結果 = 定義の式::設計の関係とプリミティブな関係の定義().評価する(&事実, &分類の事実::無い(), &表で答える定義の探索(&[]));
    assert_eq!(結果.欠け一覧.len(), 1, "{:?}", 結果.欠け一覧);
    assert_eq!(結果.欠け一覧[0].理由, 導出の欠けの理由::型引数である { 型引数名: "状態".to_string() });
    assert_eq!(結果.欠け一覧[0].導けなかった関係, 頭の関係::プリミティブな関係(プリミティブな関係の種類::保持する));
}

#[test]
fn フィールドの型の表記を落とすと保持すると命令の組を通した変換用の素材にするの答えを弱める() {
    let 答え一覧 = 定義の式::設計の関係とプリミティブな関係の定義().落とした事実が弱める答え一覧(落とした事実の種類::フィールドの型の表記);
    assert_eq!(
        答え一覧,
        vec![
            欠落が弱める答え::設計関係(関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す()),
            欠落が弱める答え::プリミティブな関係(プリミティブな関係の種類::保持する)
        ]
    );
}

#[test]
fn エンティティの識別子の関連型を落とすと識別するの答えだけを弱める() {
    let 答え一覧 = 定義の式::設計の関係とプリミティブな関係の定義().落とした事実が弱める答え一覧(落とした事実の種類::エンティティの識別子の関連型);
    assert_eq!(答え一覧, vec![欠落が弱める答え::設計関係(設計関係の結び付き方::識別する)]);
}

#[test]
fn 分類の事実を落とすと分類と命令の組を通した変換用の素材にするの答えを弱める() {
    let 答え一覧 = 定義の式::設計の関係とプリミティブな関係の定義().落とした事実が弱める答え一覧(落とした事実の種類::分類の事実);
    assert_eq!(答え一覧, vec![欠落が弱める答え::分類, 欠落が弱める答え::設計関係(関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す())]);
}

#[test]
fn 関数の役割の宣言を落とすと保持するも識別するも弱めない() {
    let 答え一覧 = 定義の式::設計の関係とプリミティブな関係の定義().落とした事実が弱める答え一覧(落とした事実の種類::関数の役割の宣言);
    assert!(答え一覧.contains(&欠落が弱める答え::設計関係(関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す())), "{答え一覧:?}");
    assert!(答え一覧.contains(&欠落が弱める答え::設計関係(関数の引数と戻り値の役目::生成する.設計関係の結び付き方へ写す())), "{答え一覧:?}");
    assert!(!答え一覧.contains(&欠落が弱める答え::プリミティブな関係(プリミティブな関係の種類::保持する)), "{答え一覧:?}");
    assert!(!答え一覧.contains(&欠落が弱める答え::設計関係(設計関係の結び付き方::識別する)), "{答え一覧:?}");
}
