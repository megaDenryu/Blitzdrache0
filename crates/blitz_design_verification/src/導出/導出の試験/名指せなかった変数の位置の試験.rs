//! 名指せなかった型を当てた変数が頭の端点か本体の途中かを、変数の名前でなく、その後の原子が変数を使うかで決めることと、
//! `表記が型を名指す` が当たっている変数へ当てようとしたら束縛を黙って落とさず止めることを固定する試験。
//! 頭の主語を表記から当ててから後の事実の原子で結合する規則では、主語の未解決は頭の関係ごと落とすため、本体の途中に数えなければならない。

use super::super::{事実の原子, 名指せなかった変数の位置, 型の表記, 定義の式, 導出の欠けの理由, 導出の規則, 本体の原子, 概念の変数, 頭の関係};
use super::super::{束縛::束縛, 評価::評価の工程};
use super::{出どころ, 型, 表で答える解決};
use crate::{プリミティブな事実, 分類の事実, 抽出元の構文, 節点の分類, 設計関係の種類};

// 本体を渡した規則で、目的語を当てた束縛へ定義をたどれない型を主語として名指させ、欠けの変数の位置を返す。
fn 主語を名指せなかった位置(本体: Vec<本体の原子>) -> 名指せなかった変数の位置 {
    let 規則 = 導出の規則 {
        名前: "試験の規則",
        頭: 頭の関係::設計関係(設計関係の種類::識別する),
        本体,
        構文: 抽出元の構文::構造体のフィールド,
    };
    let (事実, 解決) = (プリミティブな事実::default(), 表で答える解決(&[]));
    let 分類 = 節点の分類::事実から閉包を取って生成する(分類の事実::無い());
    let 工程 = 評価の工程 {
        事実: &事実,
        分類: &分類,
        解決: &解決,
        規則: &規則,
    };
    let Some(束縛) = 束縛::空().事実から当てる(概念の変数::目的語, 型("旅程"), 型の表記::型引数の無い場所で生成する("未知の型"), &出どころ(2)) else {
        panic!("何も当てていない束縛へ事実から当てられなかった: 試験の段取りが誤っている");
    };
    let 答え = 工程.名指す型を当てる(&束縛, 概念の変数::主語);
    match 答え.欠け一覧.first().map(|欠け| &欠け.理由) {
        Some(導出の欠けの理由::定義のモジュールパスを解決できなかった { 変数の位置, .. }) => *変数の位置,
        その他 => panic!("定義をたどれない型の欠けが出ていない: {その他:?}"),
    }
}

const フィールドを選ぶ: 本体の原子 = 本体の原子::事実(事実の原子::フィールドの型の表記を持つ { 持ち主: 概念の変数::目的語 });
const 主語を名指す: 本体の原子 = 本体の原子::表記が型を名指す { 型: 概念の変数::主語 };

#[test]
fn 後の原子が使わない主語の未解決は頭の端点である() {
    assert_eq!(主語を名指せなかった位置(vec![フィールドを選ぶ, 主語を名指す]), 名指せなかった変数の位置::頭の端点);
}

// 反証: 変数の名前で決めると、主語は頭の端点に数えられ、後の事実の原子で結合できずに頭の関係ごと落ちた件が欠落へ数えられない。
#[test]
fn 後の事実の原子が結合する主語の未解決は本体の途中である() {
    let 結合する = 本体の原子::事実(事実の原子::エンティティの識別子の関連型を持つ { エンティティ: 概念の変数::主語 });
    assert_eq!(主語を名指せなかった位置(vec![フィールドを選ぶ, 主語を名指す, 結合する]), 名指せなかった変数の位置::本体の途中);
}

#[test]
fn 後の原子が分類を問う主語の未解決は本体の途中である() {
    let 分類を問う = 本体の原子::分類にマーカーを持つ {
        変数: 概念の変数::主語,
        マーカー名: "Mコマンド",
    };
    assert_eq!(主語を名指せなかった位置(vec![フィールドを選ぶ, 主語を名指す, 分類を問う]), 名指せなかった変数の位置::本体の途中);
}

// 定義の式の実物の規則では、命令の組を通した消費の規則の目的語だけが後の原子(分類の問い)に使われる。
#[test]
fn 実物の規則の目的語はどれも名前によらず後の原子の使い方で位置が決まる() {
    let 後で使われる規則の数 = 定義の式::設計の関係とプリミティブな関係の定義()
        .規則一覧()
        .iter()
        .filter(|規則| {
            規則
                .本体
                .iter()
                .skip_while(|原子| **原子 != 本体の原子::表記が型を名指す { 型: 概念の変数::目的語 })
                .skip(1)
                .any(|原子| 原子.変数を使うか(概念の変数::目的語))
        })
        .count();
    assert_eq!(後で使われる規則の数, 3, "命令の組を通した消費の規則3本だけが目的語の分類を問う");
}

#[test]
#[should_panic(expected = "既に当たっている変数")]
fn 表記が型を名指す原子が当たっている変数へ当てようとしたら束縛を黙って落とさず止める() {
    let 事実 = プリミティブな事実::default();
    let 解決 = 表で答える解決(&["旅行者の出来事"]);
    let 分類 = 節点の分類::事実から閉包を取って生成する(分類の事実::無い());
    let 定義 = 定義の式::設計の関係とプリミティブな関係の定義();
    let 工程 = 評価の工程 {
        事実: &事実,
        分類: &分類,
        解決: &解決,
        規則: &定義.規則一覧()[0],
    };
    let 表記 = 型の表記::型引数の無い場所で生成する("旅行者の出来事");
    let Some(主語を当てた束縛) = 束縛::空().事実から当てる(概念の変数::主語, 型("旅程"), 表記, &出どころ(2)) else {
        panic!("何も当てていない束縛へ事実から当てられなかった: 試験の段取りが誤っている");
    };
    工程.名指す型を当てる(&主語を当てた束縛, 概念の変数::主語);
}
