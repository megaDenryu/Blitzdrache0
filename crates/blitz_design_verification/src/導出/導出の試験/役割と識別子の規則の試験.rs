//! エンティティの識別子の関連型から設計の関係を導く規則と、型引数の数が役割と合わない関数の役割の宣言の扱いの試験。段取りは親の `導出の試験` が持つ。
//! 役割ごとの型引数の位置の規則は `役割の型引数の位置の規則の試験` が持つ。

use super::super::{エンティティの識別子の関連型の宣言, プリミティブな宣言, 型の表記, 導出の欠けの理由, 関数の役割, 関数の役割の宣言};
use super::{出どころ, 型, 置き場, 表で答える定義の探索};
use crate::設計概念ノード;

#[test]
fn 識別子の関連型は識別子の型を主語にしてエンティティを識別する() {
    let プリミティブな宣言 = プリミティブな宣言 {
        エンティティの識別子の関連型一覧: vec![エンティティの識別子の関連型の宣言 {
            エンティティ: 型("旅行者"),
            表記: 型の表記::型引数の無い場所で生成する("旅行者ID"),
            出どころ: 出どころ(5),
        }],
        ..プリミティブな宣言::default()
    };
    let (表記一覧, 欠け一覧) = 表で答える定義の探索(&["旅行者ID"]).評価して表記と欠けを返す(&プリミティブな宣言);
    assert_eq!(表記一覧, vec![format!("{置き場}::旅行者ID 識別する {置き場}::旅行者")]);
    assert!(欠け一覧.is_empty());
}

#[test]
fn 型引数の数が役割と合わない宣言は位置の規則ごとに欠けを出し関係を導かない() {
    let 宣言 = 関数の役割の宣言 {
        処理: 設計概念ノード::処理として生成する(置き場, "現在地を写す"),
        役割: 関数の役割::M射影関数,
        型引数の表記一覧: vec![型の表記::型引数の無い場所で生成する("旅行者の現在地")],
        出どころ: 出どころ(7),
    };
    let プリミティブな宣言 = プリミティブな宣言 {
        関数の役割の宣言一覧: vec![宣言],
        ..プリミティブな宣言::default()
    };
    let (表記一覧, 欠け一覧) = 表で答える定義の探索(&["旅行者の現在地"]).評価して表記と欠けを返す(&プリミティブな宣言);
    assert!(表記一覧.is_empty(), "数が合わない宣言から関係を導いた: {表記一覧:?}");
    let 期待 = [0, 1].map(|位置| 導出の欠けの理由::役割の型引数の数が合わない {
        役割: 関数の役割::M射影関数,
        位置,
        読めた数: 1,
    });
    assert_eq!(欠け一覧, 期待.to_vec());
}
