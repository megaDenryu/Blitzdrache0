//! 関数の役割の宣言とエンティティの識別子の関連型から設計の関係を導く規則の試験。段取りは親の `導出の試験` が持つ。

use super::super::{エンティティの識別子の関連型の事実, プリミティブな事実, 型の表記, 定義の式, 導出の欠けの理由, 関数の役割, 関数の役割の宣言の事実};
use super::{出どころ, 型, 置き場, 表で答える解決};
use crate::設計概念;

#[test]
fn 遷移関数の宣言は型引数の位置ごとの関係と固定の遷移パラメータの消費を導き根拠に規則の名前を持つ() {
    let 名前一覧 = ["旅行者の現在地", "旅行者の意図", "歩行の規則", "旅行者の出来事", "生成の失敗"];
    let 処理 = 設計概念::処理として生成する(置き場, "歩行を遷移する");
    let 宣言 = 関数の役割の宣言の事実 {
        処理,
        役割: 関数の役割::M遷移関数,
        型引数の表記一覧: 名前一覧.map(型の表記::型引数の無い場所で生成する).to_vec(),
        出どころ: 出どころ(9),
    };
    let 事実 = プリミティブな事実 {
        関数の役割の宣言一覧: vec![宣言],
        ..プリミティブな事実::default()
    };
    let 結果 = 定義の式::設計の関係と保持するの定義().評価する(&事実, &表で答える解決(&["旅行者の現在地", "旅行者の意図", "歩行の規則", "旅行者の出来事", "生成の失敗", "遷移パラメータ"]));
    let mut 表記一覧: Vec<String> = 結果.設計関係一覧.iter().map(|関係| 関係.表記().replace(&format!("{置き場}::"), "")).collect();
    表記一覧.sort();
    let mut 期待 = [
        "消費する 旅行者の現在地",
        "生成する 旅行者の現在地",
        "消費する 旅行者の意図",
        "参照する 歩行の規則",
        "生成する 旅行者の出来事",
        "生成する 生成の失敗",
        "消費する 遷移パラメータ",
    ]
    .map(|残り| format!("歩行を遷移する {残り}"))
    .to_vec();
    期待.sort();
    assert_eq!(表記一覧, 期待);
    let 固定の入力 = 結果
        .設計関係一覧
        .iter()
        .find(|関係| 関係.目的語.識別子().名前 == "遷移パラメータ")
        .map(|関係| (関係.根拠.規則の名前, 関係.根拠.使った事実の出どころ一覧.clone()));
    assert_eq!(固定の入力, Some(("遷移関数は役割の定義が固定で受け取る遷移パラメータを消費する", vec![出どころ(9)])));
}

#[test]
fn 識別子の関連型は識別子の型を主語にしてエンティティを識別する() {
    let 事実 = プリミティブな事実 {
        エンティティの識別子の関連型一覧: vec![エンティティの識別子の関連型の事実 {
            エンティティ: 型("旅行者"),
            表記: 型の表記::型引数の無い場所で生成する("旅行者ID"),
            出どころ: 出どころ(5),
        }],
        ..プリミティブな事実::default()
    };
    let (表記一覧, 欠け一覧) = 表で答える解決(&["旅行者ID"]).評価して表記と欠けを返す(&事実);
    assert_eq!(表記一覧, vec![format!("{置き場}::旅行者ID 識別する {置き場}::旅行者")]);
    assert!(欠け一覧.is_empty());
}

#[test]
fn 型引数の数が役割と合わない宣言は位置の規則ごとに欠けを出し関係を導かない() {
    let 宣言 = 関数の役割の宣言の事実 {
        処理: 設計概念::処理として生成する(置き場, "現在地を写す"),
        役割: 関数の役割::M射影関数,
        型引数の表記一覧: vec![型の表記::型引数の無い場所で生成する("旅行者の現在地")],
        出どころ: 出どころ(7),
    };
    let 事実 = プリミティブな事実 {
        関数の役割の宣言一覧: vec![宣言],
        ..プリミティブな事実::default()
    };
    let (表記一覧, 欠け一覧) = 表で答える解決(&["旅行者の現在地"]).評価して表記と欠けを返す(&事実);
    assert!(表記一覧.is_empty(), "数が合わない宣言から関係を導いた: {表記一覧:?}");
    let 期待 = [0, 1].map(|位置| 導出の欠けの理由::役割の型引数の数が合わない {
        役割: 関数の役割::M射影関数,
        位置,
        読めた数: 1,
    });
    assert_eq!(欠け一覧, 期待.to_vec());
}
