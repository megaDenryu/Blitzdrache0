//! 命令の組を通した消費の規則の試験。段取りは親の `導出の試験` が持つ。
//! 遷移の宣言がコマンドの位置で命令の組を受け取るとき、組が保持するコマンドをその処理が消費すると導くことと、
//! 組を名乗らない型のフィールドと、組の中のコマンドを名乗らないフィールドからは消費を導かないことを固定する。

use super::super::{プリミティブな事実, 型の表記, 定義の式, 関数の役割, 関数の役割の宣言の事実};
use super::{フィールド, 出どころ, 型, 置き場, 表で答える解決};
use crate::{マーカーの実装の事実, 分類の事実, 設計概念, 設計概念への参照, 設計関係の種類};

const マーカーの置き場: &str = "blitz_design::設計解釈マーカー";

// 型の名前とマーカーの名前の組から、分類の事実を組む。
fn 分類の事実を組む(実装一覧: &[(&str, &str)]) -> 分類の事実 {
    let マーカー = |名前: &str| 設計概念への参照::トレイトとして生成する(マーカーの置き場, 名前);
    let 実装 = 実装一覧
        .iter()
        .map(|(型名, マーカー名)| マーカーの実装の事実 {
            型: 型(型名),
            マーカー: マーカー(マーカー名),
            出どころ: 出どころ(1),
        })
        .collect();
    分類の事実::生成する(vec![マーカー("Mコマンド"), マーカー("M命令の組")], 実装, Vec::new())
}

// 「胴体の命令」をコマンドの位置で受け取る遷移の宣言1件と、胴体の命令のフィールド2つ(水平移動の操作・倒し量)の事実。
fn 組を受け取る遷移の事実() -> プリミティブな事実 {
    let 宣言 = 関数の役割の宣言の事実 {
        処理: 設計概念::処理として生成する(置き場, "処理"),
        役割: 関数の役割::M遷移関数,
        型引数の表記一覧: ["状態", "胴体の命令", "規則", "パラメータ", "イベント", "失敗の理由"].map(型の表記::型引数の無い場所で生成する).to_vec(),
        出どころ: 出どころ(9),
    };
    プリミティブな事実 {
        関数の役割の宣言一覧: vec![宣言],
        フィールドの型の表記一覧: vec![フィールド("胴体の命令", "水平移動の操作", &[], 3), フィールド("胴体の命令", "倒し量", &[], 4)],
        ..プリミティブな事実::default()
    }
}

// 組を受け取る遷移の事実をその分類で評価し、処理が消費すると導いた目的語の名前を並べ替えて返す。
fn 処理が消費する型の名前一覧(分類の事実: &分類の事実) -> Vec<String> {
    let 解決 = 表で答える解決(&["状態", "胴体の命令", "規則", "パラメータ", "イベント", "失敗の理由", "水平移動の操作", "倒し量"]);
    let 結果 = 定義の式::設計の関係と保持するの定義().評価する(&組を受け取る遷移の事実(), 分類の事実, &解決);
    let mut 名前一覧: Vec<String> = 結果.設計関係一覧.iter().filter(|関係| 関係.種類 == 設計関係の種類::消費する).map(|関係| 関係.目的語.識別子().名前.clone()).collect();
    名前一覧.sort();
    名前一覧
}

#[test]
fn 命令の組が保持するコマンドを組を受け取った処理が消費する() {
    let 名前一覧 = 処理が消費する型の名前一覧(&分類の事実を組む(&[("胴体の命令", "M命令の組"), ("水平移動の操作", "Mコマンド")]));
    assert_eq!(名前一覧, vec!["パラメータ", "水平移動の操作", "状態", "胴体の命令"]);
}

// 反証: 組を名乗るかを見ないと、コマンドの位置に入った列挙が選択肢に持つ値まで処理が消費したと数え、公理が関数の役割の宣言の漏れを見落とす。
#[test]
fn 命令の組を名乗らない型のフィールドからは消費を導かない() {
    let 名前一覧 = 処理が消費する型の名前一覧(&分類の事実を組む(&[("水平移動の操作", "Mコマンド")]));
    assert_eq!(名前一覧, vec!["パラメータ", "状態", "胴体の命令"]);
}

#[test]
fn 命令の組の中のコマンドを名乗らないフィールドからは消費を導かない() {
    let 名前一覧 = 処理が消費する型の名前一覧(&分類の事実を組む(&[("胴体の命令", "M命令の組"), ("水平移動の操作", "Mコマンド")]));
    assert!(!名前一覧.contains(&"倒し量".to_string()), "{名前一覧:?}");
}

#[test]
fn 命令の組を通した消費は役割の宣言とフィールドの2つの事実を根拠に持つ() {
    let 解決 = 表で答える解決(&["状態", "胴体の命令", "規則", "パラメータ", "イベント", "失敗の理由", "水平移動の操作", "倒し量"]);
    let 結果 = 定義の式::設計の関係と保持するの定義().評価する(&組を受け取る遷移の事実(), &分類の事実を組む(&[("胴体の命令", "M命令の組"), ("水平移動の操作", "Mコマンド")]), &解決);
    let Some(関係) = 結果.設計関係一覧.iter().find(|関係| 関係.目的語.識別子().名前 == "水平移動の操作") else {
        panic!("命令の組を通した消費を導かなかった: {:?}", 結果.設計関係一覧);
    };
    assert_eq!(関係.根拠.規則の名前, "遷移関数は第2の型引数で受け取る命令の組が保持するコマンドを消費する");
    assert_eq!(関係.根拠.使った事実の出どころ一覧.iter().map(|事実| 事実.行番号).collect::<Vec<_>>(), vec![9, 3]);
    assert_eq!(関係.出どころ.行番号, 3);
}
