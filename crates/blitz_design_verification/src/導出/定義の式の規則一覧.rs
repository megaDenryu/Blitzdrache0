//! 定義の式とは、設計の関係(消費する・生成する・参照する・識別する)とプリミティブの高さの関係(保持する)を、
//! プリミティブな事実の上の規則として値で並べたもののことである(Issue #193「定義の式」)。
//!
//! 規則は、頭の関係と、本体のプリミティブな原子の連言でできている。本体の事実の原子は事実1件を選んで概念の変数と型の表記を当て、
//! `表記が型を名指す` がその表記を定義の式の読み方で読んで型を当てる。頭は当たった主語と目的語の間に関係を1件置く。
//! 規則を関数の中の場合分けでなく値で持つのは、報告が「どの規則がどの事実から導いたか」を示せるようにするためと、
//! 型の表記を持つ事実を #175 が足したときに、事実の原子と規則を足せば関係を定義できるようにするためである。
//! 分類を本体の条件に使う規則(命令の組を通した消費。`命令の組を通した消費の規則.rs`)も同じ形で書く。両端が節点の事実は、この形では書けない(`規則の本体の原子` の冒頭を見る)。
//!
//! 役割の定義の知識(型引数の位置ごとに何を消費し何を生成するか)はここに在る。遷移の役割の第1の型引数(状態)は
//! 現在の状態として消費され次の状態として生成されるため、2つの規則に現れる。
//! `M遷移関数` の第6の型引数(失敗)を生成するのは、`Err(遷移失敗結果<状態, 失敗>)` が運ぶ失敗の理由がその処理の取りうる明白な出力であるためであり、
//! 毎回は生成されないことは除外の理由にならない(`Mイベント` も毎回は生成されない)。
//! 問い合わせを伴う3つの役割の問い合わせ先と失敗の位置からは関係を導かない。宣言はジェネリックな関数を代表の問い合わせ先
//! (失敗しない問い合わせ先のトレイトのオブジェクト)で具体化して書くため、その2つの型引数は実際の問い合わせ先と失敗を名指さないためである。
use super::命令の組を通した消費の規則::命令の組を通した消費の規則一覧;
use super::役割の型引数の規則表::役割の型引数の規則表;
use super::規則の本体の原子::{事実の原子, 本体の原子, 概念の変数};
use crate::{抽出元の構文, 設計関係の種類};

/// 規則の頭の関係。設計の高さの関係か、プリミティブの高さの保持するかを区別する。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 頭の関係 {
    /// 設計の関係を1件導く。
    設計関係(設計関係の種類),
    /// 保持する関係を1件導く。
    保持する,
}

/// 定義の式の規則1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 導出の規則 {
    /// 報告と導出の根拠に出す規則の名前。
    pub 名前: &'static str,
    /// 本体が成り立つときに導く関係。
    pub 頭: 頭の関係,
    /// 連言で結ぶ原子の並び。左から順に当てる。
    pub 本体: Vec<本体の原子>,
    /// 導いた関係の出どころに書く、表記が在った構文。
    pub 構文: 抽出元の構文,
}

/// 定義の式の全体。規則を当てる順に並べる。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 定義の式 {
    規則一覧: Vec<導出の規則>,
}

impl 定義の式 {
    /// 設計の関係4語と保持するの定義。関数の役割の規則・命令の組を通した消費の規則・識別子の規則・保持するの規則の順に当てる。
    pub fn 設計の関係と保持するの定義() -> Self {
        let 役割の型引数の規則 = 役割の型引数の規則表.into_iter().map(|(名前, 役割, 位置, 種類)| 導出の規則 {
            名前,
            頭: 頭の関係::設計関係(種類),
            本体: vec![
                本体の原子::事実(事実の原子::役割の型引数を持つ {
                    役割, 位置, 処理: 概念の変数::主語
                }),
                本体の原子::表記が型を名指す { 型: 概念の変数::目的語 },
            ],
            構文: 抽出元の構文::関数の役割の型引数,
        });
        let 残りの規則 = [
            導出の規則 {
                名前: "識別子の関連型が名指す型はそのエンティティを識別する",
                頭: 頭の関係::設計関係(設計関係の種類::識別する),
                本体: vec![
                    本体の原子::事実(事実の原子::エンティティの識別子の関連型を持つ {
                        エンティティ: 概念の変数::目的語
                    }),
                    本体の原子::表記が型を名指す { 型: 概念の変数::主語 },
                ],
                構文: 抽出元の構文::エンティティの識別子の関連型,
            },
            導出の規則 {
                名前: "フィールドの型が名指す型を持ち主が保持する",
                頭: 頭の関係::保持する,
                本体: vec![本体の原子::事実(事実の原子::フィールドの型の表記を持つ { 持ち主: 概念の変数::主語 }), 本体の原子::表記が型を名指す { 型: 概念の変数::目的語 }],
                構文: 抽出元の構文::構造体のフィールド,
            },
        ];
        Self {
            規則一覧: 役割の型引数の規則.chain(命令の組を通した消費の規則一覧()).chain(残りの規則).collect(),
        }
    }

    /// 当てる順に並んだ規則。
    pub fn 規則一覧(&self) -> &[導出の規則] {
        &self.規則一覧
    }
}
