//! プリミティブな宣言とは、抽出器がRustのソースから読む、コンパイラが知っている形の宣言のことである(Issue #193 の契約)。
//! 型の定義・フィールドの型の表記・関数の役割の宣言・エンティティの識別子の関連型の4種を持つ。マーカーの実装と上位トレイトの宣言は
//! 同じ高さの宣言であり、`設計解釈マーカーの宣言の一覧` が持つ。
//!
//! **宣言は設計の意味を持たない。** フィールドの型の表記は包みを剥がす前の書かれた文字列のまま運び、何を保持するかは定義の式が決める。
//! 関数の役割の宣言は型引数の書かれた文字列を並びのまま運び、どの位置が何を変換用の素材にするかは定義の式が決める。
//! 型の表記を持つ宣言を足すときは、この型へ一覧を1つ足し、宣言の原子と定義の式の規則を足せば足せる。
//! 両端がノードの関係(「呼ぶ」「コンポジションルートが組む」等)と、付いているマーカーと組み合わせる定義は、束縛・結果・評価器の拡張が要る(`規則の本体の原子` の冒頭を見る)。

#[path = "プリミティブな宣言の定義/型についての宣言の定義.rs"]
mod 型についての宣言の定義;
#[path = "プリミティブな宣言の定義/関数の役割の宣言の定義.rs"]
mod 関数の役割の宣言の定義;

use crate::設計概念ノード;

pub use 型についての宣言の定義::{エンティティの識別子の関連型の宣言, フィールドの型の表記の宣言, 型の定義};
pub use 関数の役割の宣言の定義::関数の役割の宣言;

/// ソースに書かれた型の表記1件。包みを剥がす前の書かれた文字列と、その表記を書いた場所で有効な型引数の名前の一覧を持つ。
/// 型引数の名前を持つのは、`struct 包み<状態> { 中身: 状態 }` の `状態` が設計概念でなく型引数であることを、定義の式が表記だけから見分けるためである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 型の表記 {
    書かれた文字列: String,
    有効な型引数名一覧: Vec<String>,
}

/// 抽出器が出すプリミティブな宣言の全体。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct プリミティブな宣言 {
    型の定義一覧: Vec<型の定義>,
    フィールドの型の表記一覧: Vec<フィールドの型の表記の宣言>,
    エンティティの識別子の関連型一覧: Vec<エンティティの識別子の関連型の宣言>,
    関数の役割の宣言一覧: Vec<関数の役割の宣言>,
}

impl 型の表記 {
    /// 書かれた文字列と、その表記を書いた場所で有効な型引数の名前の一覧から組む。
    pub fn 生成する(書かれた文字列: &str, 有効な型引数名一覧: Vec<String>) -> Self {
        Self {
            書かれた文字列: 書かれた文字列.to_string(),
            有効な型引数名一覧,
        }
    }

    /// 型引数を導入しない場所(関数の役割の型引数・関連型の右辺)に書いた表記を組む。
    pub fn 型引数の無い場所で生成する(書かれた文字列: &str) -> Self {
        Self::生成する(書かれた文字列, Vec::new())
    }

    /// 包みを剥がす前の書かれた文字列。
    pub fn 書かれた文字列(&self) -> &str {
        &self.書かれた文字列
    }

    /// その表記を書いた場所で有効な型引数の名前の一覧。
    pub fn 有効な型引数名一覧(&self) -> &[String] {
        &self.有効な型引数名一覧
    }
}

impl プリミティブな宣言 {
    /// 型の定義を1件足す。
    pub fn 型の定義を足す(&mut self, 型の定義: 型の定義) {
        self.型の定義一覧.push(型の定義);
    }

    /// フィールドの型の表記の宣言を1件足す。
    pub fn フィールドの型の表記を足す(&mut self, 宣言: フィールドの型の表記の宣言) {
        self.フィールドの型の表記一覧.push(宣言);
    }

    /// エンティティの識別子の関連型の宣言を1件足す。
    pub fn エンティティの識別子の関連型を足す(&mut self, 宣言: エンティティの識別子の関連型の宣言) {
        self.エンティティの識別子の関連型一覧.push(宣言);
    }

    /// 関数の役割の宣言を1件足す。
    pub fn 関数の役割の宣言を足す(&mut self, 宣言: 関数の役割の宣言) {
        self.関数の役割の宣言一覧.push(宣言);
    }

    /// 型の定義の一覧を置き換えた宣言を返す。既定の値から一覧を1つずつ置き換えて組むために使う。
    pub fn 型の定義一覧を置き換える(self, 型の定義一覧: Vec<型の定義>) -> Self {
        Self { 型の定義一覧, ..self }
    }

    /// フィールドの型の表記の宣言の一覧を置き換えた宣言を返す。
    pub fn フィールドの型の表記一覧を置き換える(self, フィールドの型の表記一覧: Vec<フィールドの型の表記の宣言>) -> Self {
        Self { フィールドの型の表記一覧, ..self }
    }

    /// エンティティの識別子の関連型の宣言の一覧を置き換えた宣言を返す。
    pub fn エンティティの識別子の関連型一覧を置き換える(self, エンティティの識別子の関連型一覧: Vec<エンティティの識別子の関連型の宣言>) -> Self {
        Self {
            エンティティの識別子の関連型一覧, ..self
        }
    }

    /// 関数の役割の宣言の一覧を置き換えた宣言を返す。
    pub fn 関数の役割の宣言一覧を置き換える(self, 関数の役割の宣言一覧: Vec<関数の役割の宣言>) -> Self {
        Self { 関数の役割の宣言一覧, ..self }
    }

    /// 型の定義の一覧を読む。
    pub fn 型の定義一覧(&self) -> &[型の定義] {
        &self.型の定義一覧
    }

    /// フィールドの型の表記の宣言の一覧を読む。
    pub fn フィールドの型の表記一覧(&self) -> &[フィールドの型の表記の宣言] {
        &self.フィールドの型の表記一覧
    }

    /// エンティティの識別子の関連型の宣言の一覧を読む。
    pub fn エンティティの識別子の関連型一覧(&self) -> &[エンティティの識別子の関連型の宣言] {
        &self.エンティティの識別子の関連型一覧
    }

    /// 関数の役割の宣言の一覧を読む。
    pub fn 関数の役割の宣言一覧(&self) -> &[関数の役割の宣言] {
        &self.関数の役割の宣言一覧
    }

    /// 他の宣言を自分の後ろへ併せる。抽出器が規則ごとに読んだ宣言を1つへまとめるために使う。
    pub fn 併せる(&mut self, 他: Self) {
        self.型の定義一覧.extend(他.型の定義一覧);
        self.フィールドの型の表記一覧.extend(他.フィールドの型の表記一覧);
        self.エンティティの識別子の関連型一覧.extend(他.エンティティの識別子の関連型一覧);
        self.関数の役割の宣言一覧.extend(他.関数の役割の宣言一覧);
    }

    /// 宣言そのものが立てるノード。関数の役割の宣言が処理のノードを、型の定義が型のノードを立てる。関係に参加しない定義もノードとして在る。
    pub fn 宣言が立てる概念一覧(&self) -> Vec<設計概念ノード> {
        let 処理 = self.関数の役割の宣言一覧.iter().map(|宣言| 宣言.処理().clone());
        処理.chain(self.型の定義一覧.iter().map(|定義| 定義.型().clone())).collect()
    }
}
