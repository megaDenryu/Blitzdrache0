//! 型の名前の定義の探索とは、型の表記を書いた場所から見て、その名前の型の定義がどのモジュールに在るかを答える口のことである。
//!
//! **定義の探索を事実の値でなく口にするのは、どの名前の定義を探すかを定義の式が決めるためである。** 包みを剥がして芯の名前を採るのは定義の式の知識であり、
//! 事実の側(抽出器)は剥がす前の書かれた文字列しか知らない。したがって抽出器が先回りして名前の定義を探しておくことはできず、定義の式の評価器が
//! 芯の名前を採った時点で、この口へ問う。探し方そのもの(同じファイルの定義・`use` の取り込み・同名の定義の候補の選び方)は Rust が名前から定義を探す規則であり、
//! このクレートは抽出器(`xtask`)を知らないため持たない。抽出器が、自分の構文解析器でこの口を実装する。
//! 口がトレイトであるのは、実装が抽出器のソース群と試験の表の2つに分かれ、評価器がどちらにも同じ問いを投げるためである。

use crate::事実の出どころ;

/// 型の表記を書いた場所から見た、型の名前の定義の在り処を答える口。
pub trait 型の名前の定義の探索 {
    /// 参照元から見たその名前の型の定義を書いたモジュールのパスの表記(`blitz_game::移動`)。定義をたどれなければ無しを返す(適用範囲の外のクレートを含む)。
    fn 型の定義のモジュールパスを探す(&self, 型名: &str, 参照元: &事実の出どころ) -> Option<String>;
}
