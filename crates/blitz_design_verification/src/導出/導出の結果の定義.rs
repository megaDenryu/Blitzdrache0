//! 導出の結果とは、定義の式をプリミティブな事実の上で評価して得た、関係と、関係の端点の節点と、導けなかった箇所の一覧のことである。
//!
//! 導けなかった箇所(導出の欠け)を結果へ載せるのは、型の表記を読めなかったことや定義をたどれなかったことを黙って落とさず、
//! 抽出器が自分の欠けの一覧へ写して数えられるようにするためである。どの欠けが関係そのものを失ったかは抽出器の区分が決め、
//! その区分が `関係を落とした抽出の欠落` を通って、欠けた事実に依存する関係の不在を未決定へ倒す。
//! 欠けは、それを本体に持つ規則の頭の関係を持つ。欠けが弱めるのはその規則が導く関係の答えだけであり、無関係な関係の答えを倒さないためである。
//! 本体が成り立った束縛から頭の関係を1件導いてこの結果へ足す操作もここに置く。足す先の一覧(設計関係かプリミティブな関係か)を選ぶのが頭の関係であり、
//! 足す操作が結果の一覧の形を知っているためである。

use super::型の表記を読めない理由の定義::型の表記を読めない理由;
use super::定義の式の規則一覧::{導出の規則, 頭の関係};
use super::束縛::束縛;
use super::関数の役割の定義::関数の役割;
use crate::{プリミティブな関係, 事実の出どころ, 導出の根拠, 抽出の出どころ, 設計概念, 設計関係};

/// 定義の式を評価して得たもの。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct 導出の結果 {
    /// 導いた関係の端点の節点。同じ節点が2度現れてよく、重複のまとめはグラフの組み立てが行う。
    pub 端点の概念一覧: Vec<設計概念>,
    /// 導いた設計関係。
    pub 設計関係一覧: Vec<設計関係>,
    /// 導いたプリミティブな関係。
    pub プリミティブな関係一覧: Vec<プリミティブな関係>,
    /// 規則の本体を評価する途中で導けなかった箇所。
    pub 欠け一覧: Vec<導出の欠け>,
}

/// 規則の本体を評価する途中で、事実から型の表記を当てられなかったか、型の表記から型を名指せなかった1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 導出の欠け {
    /// その表記が書かれていた場所。
    pub 出どころ: 事実の出どころ,
    /// 名指せなかった理由。
    pub 理由: 導出の欠けの理由,
    /// 欠けた箇所を本体に持つ規則の頭の関係。抽出器はこの関係の答えだけを弱める欠落へ写す。
    pub 導けなかった関係: 頭の関係,
}

/// 事実から型の表記を当てられなかったか、型の表記から型を名指せなかった理由。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 導出の欠けの理由 {
    /// 関数の役割の宣言の型引数の数が、その役割が取る数と合わない。どの位置の表記が何を指すかを決められないため、位置の規則はその宣言から関係を導かない。
    役割の型引数の数が合わない {
        /// 宣言の役割。
        役割: 関数の役割,
        /// 表記を当てようとした規則の型引数の位置。0始まりである。
        位置: usize,
        /// 宣言が持っていた型引数の数。
        読めた数: usize,
    },
    /// 定義の式がその表記を読めない。関係そのものを導けない。
    型の表記を読めない(型の表記を読めない理由),
    /// 定義の式の署名の読み方が、関数の署名の型の表記を読めない。関係そのものを導けない。
    関数の署名の型の表記を読めない(型の表記を読めない理由),
    /// 関数の署名の型の表記が、それを書いた場所で有効な型引数の名前である。関数は何かの型を実際に扱っており、どの型かを名指せないため関係を導けない。
    関数の署名の型引数である {
        /// 一致した型引数の名前。
        型引数名: String,
    },
    /// 表記が、それを書いた場所で有効な型引数の名前である。実在しない設計概念の節点を作らないために関係を導かない。
    型引数である {
        /// 一致した型引数の名前。
        型引数名: String,
    },
    /// 型の定義をたどれず、節点のモジュールパスを空にした。節点は落とさない。関係を導くかは、空の節点を当てた変数の位置で決まる。
    定義のモジュールパスを解決できなかった {
        /// 定義を探した名前。フレーム型なら座標系を落とした名前である。
        型名: String,
        /// 空の節点を当てた変数が、規則の中でどう使われるか。
        変数の位置: 名指せなかった変数の位置,
    },
}

/// 定義をたどれなかった型を当てた変数が、規則の中でどう使われるか。
///
/// 分類の事実はマーカーの実装が名指した型の節点へ付き、その実装が定義をたどれていれば空の節点には付かない。そのため分類を問われる変数と、
/// 頭に現れず後の事実をつなぐ変数へ空の節点を当てると、本体が成り立たずに頭の関係ごと落ちうる。落ちた関係はグラフへ入らないため、
/// その関係の答えを弱めなければ辺の不在から偽の反証が出る。本体が成り立つ場合も弱める。弱めるとその規則の頭の関係の答えを全部弱め、その種類の関係を問う原子は、どの主語と目的語についても辺の不在を根拠に答えなくなる。それでも弱めるのは、偽の反証が正しいコードを直しに行かせるのに比べ、答えを未決定に留める方が害が小さいためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 名指せなかった変数の位置 {
    /// 頭の主語か目的語であり、分類を問われない。関係は空の節点を端点にしてグラフへ入り、その節点に触れた問いは別に未決定で答える。
    頭の端点,
    /// 頭に現れない経由する概念か、分類を問われる変数である。本体が成り立たず、頭の関係ごと落ちる。
    本体の途中,
}

impl 導出の結果 {
    /// 本体が成り立った束縛1つから頭の関係を1件導き、その両端の節点とともにこの結果へ足す。
    pub(super) fn 規則の頭を足す(&mut self, 規則: &導出の規則, 束縛: &束縛) {
        let (Some((主語, 目的語)), Some(最後に使った事実の出どころ)) = (束縛.主語と目的語(), 束縛.使った事実().last()) else {
            panic!("規則「{}」の本体が頭の主語と目的語と事実を当てていない: 定義の式の規則は本体で頭の変数を全部当てるという不変条件が破れた", 規則.名前);
        };
        let 出どころ = 抽出の出どころ {
            パス: 最後に使った事実の出どころ.パス.clone(),
            行番号: 最後に使った事実の出どころ.行番号,
            構文: 規則.構文,
        };
        let 根拠 = 導出の根拠::生成する(規則.名前, 束縛.使った事実().to_vec());
        self.端点の概念一覧.extend([設計概念::参照から生成する(主語.clone()), 設計概念::参照から生成する(目的語.clone())]);
        match 規則.頭 {
            頭の関係::設計関係(種類) => self.設計関係一覧.push(設計関係 {
                主語: 主語.clone(),
                種類,
                目的語: 目的語.clone(),
                出どころ,
                根拠,
            }),
            頭の関係::プリミティブな関係(種類) => self.プリミティブな関係一覧.push(プリミティブな関係 {
                主語: 主語.clone(),
                種類,
                目的語: 目的語.clone(),
                出どころ,
                根拠,
            }),
        }
    }
}
