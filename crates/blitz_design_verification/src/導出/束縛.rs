//! 束縛とは、規則の本体を左から当てていく途中で、概念の変数と型の表記へ何を当てたかと、そのために使った事実の出どころを持つ値のことである。
//!
//! 当てるたびに新しい値を返すのは、1つの束縛から事実の候補ごとに別々の束縛が分かれるためである。

use super::規則の本体の原子::概念の変数;
use super::関係を導く事実::型の表記;
use crate::{事実の出どころ, 設計概念への参照};

/// 規則の本体を当てる途中の割り当て。
#[derive(Debug, Clone, Default)]
pub(super) struct 束縛 {
    主語: Option<設計概念への参照>,
    目的語: Option<設計概念への参照>,
    表記: Option<(型の表記, 事実の出どころ)>, // 当てた型の表記と、その表記が書かれていた場所
    使った事実: Vec<事実の出どころ>,
}

impl 束縛 {
    /// 何も当てていない束縛。規則の本体の評価がここから始まる。
    pub(super) fn 空() -> Self {
        Self::default()
    }

    /// その変数へ概念を当てた束縛。既に別の概念が当たっていれば、連言が成り立たないため無しを返す。
    pub(super) fn 概念を当てる(&self, 変数: 概念の変数, 参照: 設計概念への参照) -> Option<Self> {
        let 当たっている = match 変数 {
            概念の変数::主語 => &self.主語,
            概念の変数::目的語 => &self.目的語,
        };
        if 当たっている.as_ref().is_some_and(|在る| *在る != 参照) {
            return None;
        }
        let mut 次 = self.clone();
        match 変数 {
            概念の変数::主語 => 次.主語 = Some(参照),
            概念の変数::目的語 => 次.目的語 = Some(参照),
        }
        Some(次)
    }

    /// 事実1件を使って、変数へ概念を、表記へ型の表記を当てた束縛。使った事実の出どころを並びの末尾へ足す。
    pub(super) fn 事実から当てる(&self, 変数: 概念の変数, 参照: 設計概念への参照, 表記: 型の表記, 出どころ: &事実の出どころ) -> Option<Self> {
        let mut 次 = self.概念を当てる(変数, 参照)?;
        次.表記 = Some((表記, 出どころ.clone()));
        次.使った事実.push(出どころ.clone());
        Some(次)
    }

    /// 当てた型の表記と、その表記が書かれていた場所。
    pub(super) fn 表記(&self) -> Option<&(型の表記, 事実の出どころ)> {
        self.表記.as_ref()
    }

    /// 頭の主語と目的語。どちらかが当たっていなければ無しである。
    pub(super) fn 主語と目的語(&self) -> Option<(&設計概念への参照, &設計概念への参照)> {
        Some((self.主語.as_ref()?, self.目的語.as_ref()?))
    }

    /// 使った事実の出どころを使った順に並べた一覧。
    pub(super) fn 使った事実(&self) -> &[事実の出どころ] {
        &self.使った事実
    }
}
