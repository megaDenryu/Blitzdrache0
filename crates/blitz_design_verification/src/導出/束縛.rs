//! 束縛とは、規則の本体を左から当てていく途中で、概念の変数と型の表記へ何を当てたかと、そのために使った事実の出どころを持つ値のことである。
//!
//! 当てるたびに新しい値を返すのは、1つの束縛から事実の候補ごとに別々の束縛が分かれるためである。

use super::プリミティブな事実の定義::型の表記;
use super::規則の本体の原子::概念の変数;
use crate::{事実の出どころ, 設計概念への参照};

/// 規則の本体を当てる途中の割り当て。
#[derive(Debug, Clone, Default)]
pub(super) struct 束縛 {
    主語: Option<設計概念への参照>,
    目的語: Option<設計概念への参照>,
    表記: Option<(型の表記, 事実の出どころ)>, // 当てた型の表記と、その表記が書かれていた場所
    使った事実: Vec<事実の出どころ>,
}

impl 束縛 {
    /// 何も当てていない束縛。規則の本体の評価がここから始まる。
    pub(super) fn 空() -> Self {
        Self::default()
    }

    // その変数へ概念を当てた束縛。既に別の概念が当たっていれば、連言が成り立たないため無しを返す。
    fn 概念を当てる(&self, 変数: 概念の変数, 参照: 設計概念への参照) -> Option<Self> {
        if self.当たっている概念(変数).is_some_and(|在る| *在る != 参照) {
            return None;
        }
        Some(self.書き込んだ束縛(変数, 参照))
    }

    /// まだ何も当たっていない変数へ概念を当てた束縛。`表記が型を名指す` が使う。
    /// 定義の式の規則は、この原子が当てる変数を先の原子に当てさせない。当たっている変数へ当てようとしたなら、規則の並びの不変条件が破れている。
    pub(super) fn 空いている変数へ当てる(&self, 変数: 概念の変数, 参照: 設計概念への参照) -> Self {
        if let Some(在る) = self.当たっている概念(変数) {
            panic!(
                "`表記が型を名指す` が既に当たっている変数 {変数:?} ({}) へ {} を当てようとした: 定義の式の規則はこの原子が当てる変数を先の原子に当てさせないという不変条件が破れた",
                在る.表記(),
                参照.表記()
            );
        }
        self.書き込んだ束縛(変数, 参照)
    }

    // その変数へ概念を書き込んだ新しい束縛。当たっているかの判定は呼び出し側が済ませている。
    fn 書き込んだ束縛(&self, 変数: 概念の変数, 参照: 設計概念への参照) -> Self {
        let mut 次 = self.clone();
        match 変数 {
            概念の変数::主語 => 次.主語 = Some(参照),
            概念の変数::目的語 => 次.目的語 = Some(参照),
        }
        次
    }

    // その変数に当たっている概念。
    fn 当たっている概念(&self, 変数: 概念の変数) -> Option<&設計概念への参照> {
        match 変数 {
            概念の変数::主語 => self.主語.as_ref(),
            概念の変数::目的語 => self.目的語.as_ref(),
        }
    }

    /// 事実1件を使って、変数へ概念を、表記へ型の表記を当てた束縛。使った事実の出どころを並びの末尾へ足す。
    pub(super) fn 事実から当てる(&self, 変数: 概念の変数, 参照: 設計概念への参照, 表記: 型の表記, 出どころ: &事実の出どころ) -> Option<Self> {
        let mut 次 = self.概念を当てる(変数, 参照)?;
        次.表記 = Some((表記, 出どころ.clone()));
        次.使った事実.push(出どころ.clone());
        Some(次)
    }

    /// 当てた型の表記と、その表記が書かれていた場所。
    pub(super) fn 表記(&self) -> Option<&(型の表記, 事実の出どころ)> {
        self.表記.as_ref()
    }

    /// 頭の主語と目的語。どちらかが当たっていなければ無しである。
    pub(super) fn 主語と目的語(&self) -> Option<(&設計概念への参照, &設計概念への参照)> {
        Some((self.主語.as_ref()?, self.目的語.as_ref()?))
    }

    /// 使った事実の出どころを使った順に並べた一覧。
    pub(super) fn 使った事実(&self) -> &[事実の出どころ] {
        &self.使った事実
    }
}
