//! 関数の役割の宣言を、規則の本体の宣言の原子 `役割の型引数を持つ` で選ぶ工程。受け取るのは役割と型引数の位置と関数を当てる変数と束縛、
//! 返すのは宣言ごとに当てた束縛と、型引数の数が役割の取る数と合わない宣言の欠けである。
//! 評価の工程(`評価`)から分けるのは、宣言の型引数の数を確かめる規律がこの宣言の原子だけに属し、他の原子の評価と触れる状態が違うためである。

use super::原子の答えの定義::原子の答え;
use super::型の名前の定義の探索の定義::型の名前の定義の探索;
use super::導出の結果の定義::{導出の欠け, 導出の欠けの理由};
use super::束縛::束縛;
use super::規則の本体の原子::概念の変数;
use super::評価::評価の工程;
use super::関数の役割の定義::関数の役割;

impl<探索: 型の名前の定義の探索> 評価の工程<'_, 探索> {
    // その役割の宣言ごとに、その位置の型引数の表記を当てる。宣言の型は、型引数の数が役割の取る数と等しいことを
    // 構築のときに確かめないため、評価器がここで確かめる。数が合わない宣言はどの位置の表記が何を指すかを決められないため、束縛を作らず欠けとして返す。
    pub(super) fn 役割の型引数を当てる(&self, 役割: 関数の役割, 位置: usize, 処理: 概念の変数, 束縛: &束縛) -> 原子の答え {
        let mut 答え = 原子の答え::default();
        for 件 in self.プリミティブな宣言().関数の役割の宣言一覧().iter().filter(|件| 件.役割() == 役割) {
            let 読めた数 = 件.型引数の表記一覧().len();
            match 件.型引数の表記一覧().get(位置) {
                Some(表記) if 役割.型引数の数を受け取れるか(読めた数) => 答え.束縛を足す(束縛.宣言から当てる(処理, 件.処理().参照を組む(), 表記.clone(), 件.出どころ())),
                _ => 答え.欠けを足す(導出の欠け::生成する(件.出どころ().clone(), 導出の欠けの理由::役割の型引数の数が合わない { 役割, 位置, 読めた数 }, self.規則().頭())),
            }
        }
        答え
    }
}
