//! 抽出が事実を1件読めなかったとき、どの答えが不在を根拠にできなくなるかを、定義の式の規則から求める工程。
//! 受け取るのは読めなかった事実の種類、返すのはその種類の事実を本体で読む規則の頭の答えの並びである。
//!
//! 求め方を規則から導き、事実の種類と関係の種類の対応を表で持たないのは、規則を足したときに表を直し忘れると、
//! 新しい規則が導く関係の答えが、その事実を落としても弱まらずに不在から反証されるためである。
//! 命令の組を通した消費の規則はフィールドの事実と分類を本体で読むため、フィールドか分類を落とした件は保持するに加えて変換用の素材にするの答えも弱める。

use super::定義の式の規則一覧::定義の式;
use super::規則の本体の原子::{事実の原子, 本体の原子};
use crate::欠落が弱める答え;

/// 抽出が読めなかった事実の種類。定義の式の規則の本体が読む事実と、分類の事実である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 落とした事実の種類 {
    /// 型の定義のフィールドの型の表記。
    フィールドの型の表記,
    /// エンティティの識別子の関連型。
    エンティティの識別子の関連型,
    /// 関数の役割の宣言。
    関数の役割の宣言,
    /// 関数の署名。
    関数の署名,
    /// マーカーの実装と上位トレイトの宣言。
    分類の事実,
}

impl 定義の式 {
    /// その種類の事実を落とした件が弱める答えの並び。その事実を本体で読む規則の頭の答えを重ねずに並べ、分類の事実なら分類の答えも並べる。
    pub fn 落とした事実が弱める答え一覧(&self, 種類: 落とした事実の種類) -> Vec<欠落が弱める答え> {
        let mut 答え一覧 = if 種類 == 落とした事実の種類::分類の事実 { vec![欠落が弱める答え::分類] } else { Vec::new() };
        for 規則 in self.規則一覧().iter().filter(|規則| 規則.本体.iter().any(|原子| 原子がその事実を読むか(*原子, 種類))) {
            let 答え = 欠落が弱める答え::規則の頭から求める(規則.頭);
            if !答え一覧.contains(&答え) {
                答え一覧.push(答え);
            }
        }
        答え一覧
    }
}

// 規則の本体の原子1つが、その種類の事実を読むか。`表記が型を名指す` は事実を読まず、先の事実の原子が当てた表記を読む。
const fn 原子がその事実を読むか(原子: 本体の原子, 種類: 落とした事実の種類) -> bool {
    matches!(
        (原子, 種類),
        (本体の原子::事実(事実の原子::フィールドの型の表記を持つ { .. }), 落とした事実の種類::フィールドの型の表記)
            | (本体の原子::事実(事実の原子::エンティティの識別子の関連型を持つ { .. }), 落とした事実の種類::エンティティの識別子の関連型)
            | (本体の原子::事実(事実の原子::役割の型引数を持つ { .. }), 落とした事実の種類::関数の役割の宣言)
            | (
                本体の原子::事実(
                    事実の原子::署名の所有者の型を持つ { .. }
                        | 事実の原子::署名の所有者のトレイトを持つ { .. }
                        | 事実の原子::署名の受け手の型を持つ { .. }
                        | 事実の原子::署名の受け手のトレイトを持つ { .. }
                        | 事実の原子::署名の引数を持つ { .. }
                        | 事実の原子::署名の戻り値を持つ { .. }
                ),
                落とした事実の種類::関数の署名
            )
            | (本体の原子::分類にマーカーを持つ { .. }, 落とした事実の種類::分類の事実)
    )
}
