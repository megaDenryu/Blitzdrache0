//! 規則の本体の原子 `署名の表記が型を名指す` を1つの束縛へ当てる工程。受け取るのは束縛と当てる変数と読み通す範囲、返すのは名指した型とトレイトごとに分かれた束縛と、読めなかった欠けである。
//!
//! 表記は署名の読み方(`署名の型の表記の読み方`)で読む。1つの表記が複数の型を名指しうる(`Result<T, E>`・組)ため、束縛は名指したものの数だけ分かれる。
//! 読む前に、トレイトの境界を持つ型引数とその関連型を境界のトレイトへ読み替える(`型引数の境界`)。`fn f<C: Mコマンド>(c: C)` は `fn f(c: impl Mコマンド)` と同じ意味であり、
//! 署名の読み方が `impl` の境界のトレイトを読むのと揃えるためである。
//! 読めない表記と、読み替えた後に残る型引数の名前(トレイトの境界を持たない型引数)は、関係を導かずに欠けとして返す。
//! 境界を持たない型引数(`fn f<T>(t: T)`)は、どの設計概念も名指さない。抽出器はこの欠けを、設計概念でないため明示して除外した区分に数え、件数を残す。
//! 名指した型とトレイトの定義の在り処は、フィールドの読み方と同じ解決の口へ問う(`名指した型を当てる`)。
//! パスの修飾が付いた名前は、修飾を解決の口へ問う(`修飾された名前を解決する`)。修飾が標準ライブラリを指すなら関係を導かず、型の関連項目なら読めない表記として欠けに数え、
//! 定義をたどれなければフィールドの読み方の未解決と同じくモジュールパスを空にした節点を当てて欠けを1件添える。

use super::名指す型の読み取り::当てた表記;
use super::型の名前の解決の定義::{修飾された名前の解決, 型の名前の解決};
use super::型の表記を読めない理由の定義::型の表記を読めない理由;
use super::導出の結果の定義::導出の欠けの理由;
use super::束縛::束縛;
use super::署名の型の表記の読み方::{署名の型の表記の読み取り, 署名の型の表記を読む, 署名の読み通す範囲};
use super::表記が名指す型の定義::表記が名指す型;
use super::規則の本体の原子::概念の変数;
use super::評価::{原子の答え, 評価の工程};
use crate::Rustの項目の種類;

impl<解決: 型の名前の解決> 評価の工程<'_, 解決> {
    /// 束縛が当てた関数の署名の型の表記を署名の読み方でその範囲まで読み、名指す型かトレイトのそれぞれをその変数へ当てる。
    pub(super) fn 署名の表記が名指す型を当てる(&self, 束縛: &束縛, 変数: 概念の変数, 範囲: 署名の読み通す範囲) -> 原子の答え {
        let (表記, 出どころ) = 当てた表記(束縛);
        let mut 答え = 原子の答え::default();
        for 読み取り in 署名の型の表記を読む(&表記.型引数を境界へ読み替えた書かれた文字列(), 範囲) {
            let (名指したもの, 種類) = match 読み取り {
                署名の型の表記の読み取り::読めない(理由) => {
                    答え.併せる(self.欠けの答え(出どころ, 導出の欠けの理由::関数の署名の型の表記を読めない(理由)));
                    continue;
                }
                署名の型の表記の読み取り::修飾された名前 { 修飾, 名前, 種類 } => {
                    答え.併せる(self.修飾された名前を当てる(束縛, 変数, &修飾, &名前, 種類));
                    continue;
                }
                署名の型の表記の読み取り::型(型) => (型, Rustの項目の種類::型),
                署名の型の表記の読み取り::トレイト(トレイト) => (トレイト, Rustの項目の種類::トレイト),
            };
            if let Some(型引数名) = 名指したもの.宣言の型引数と一致する名前(表記.有効な型引数名一覧()) {
                答え.併せる(self.欠けの答え(出どころ, 導出の欠けの理由::関数の署名の型引数である { 型引数名 }));
                continue;
            }
            答え.併せる(self.名指した型を当てる(束縛, 変数, &名指したもの, 種類));
        }
        答え
    }

    // パスの修飾が付いた名前を、修飾の解決の答えに従って変数へ当てる。修飾の頭が書いた場所の型引数の名前なら、名前はその型引数の関連項目であり、口へ問わない。
    fn 修飾された名前を当てる(&self, 束縛: &束縛, 変数: 概念の変数, 修飾: &str, 名前: &表記が名指す型, 種類: Rustの項目の種類) -> 原子の答え {
        let (表記, 出どころ) = 当てた表記(束縛);
        let 頭 = 修飾.split("::").next().unwrap_or_default().trim();
        let 解決 = if 表記.有効な型引数名一覧().iter().any(|型引数名| 型引数名 == 頭) {
            修飾された名前の解決::型の関連項目である
        } else {
            self.解決.修飾された名前を解決する(修飾, 名前.定義を探す名前(), 種類, 出どころ)
        };
        match 解決 {
            修飾された名前の解決::標準ライブラリの項目である => 原子の答え::default(),
            修飾された名前の解決::型の関連項目である => {
                let 表記 = format!("{修飾}::{}", 名前.同一性の名前());
                self.欠けの答え(出どころ, 導出の欠けの理由::関数の署名の型の表記を読めない(型の表記を読めない理由::型の表記にパスの修飾がある { 表記 }))
            }
            修飾された名前の解決::定義がある { モジュールパス } => self.在り処の分かった型を当てる(束縛, 変数, 名前, 種類, Some(モジュールパス)),
            修飾された名前の解決::定義をたどれない => self.在り処の分かった型を当てる(束縛, 変数, 名前, 種類, None),
        }
    }
}
