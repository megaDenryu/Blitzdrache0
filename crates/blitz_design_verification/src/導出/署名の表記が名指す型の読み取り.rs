//! 規則の本体の原子 `署名の表記が型を名指す` を1つの束縛へ当てる工程。受け取るのは束縛と当てる変数、返すのは名指した型とトレイトごとに分かれた束縛と、読めなかった欠けである。
//!
//! 表記は署名の読み方(`署名の型の表記の読み方`)で読む。1つの表記が複数の型を名指しうる(`Result<T, E>`・組)ため、束縛は名指したものの数だけ分かれる。
//! 読む前に、トレイトの境界を持つ型引数とその関連型を境界のトレイトへ読み替える(`型引数の境界`)。`fn f<C: Mコマンド>(c: C)` は `fn f(c: impl Mコマンド)` と同じ意味であり、
//! 署名の読み方が `impl` の境界のトレイトを読むのと揃えるためである。
//! 読めない表記と、読み替えた後に残る型引数の名前(トレイトの境界を持たない型引数)は、関係を導かずに欠けとして返す。フィールドの読み方と違い、型引数の名前も読めない表記として数える。
//! 境界を持たない総称の関数(`fn f<T>(t: T)`)は何かの型を実際に引数に取っており、どの型かを名指せないことは、黙って除外してよい条件ではないためである。
//! 名指した型とトレイトの定義の在り処は、フィールドの読み方と同じ解決の口へ問う(`名指した型を当てる`)。

use super::名指す型の読み取り::当てた表記;
use super::型の名前の解決の定義::型の名前の解決;
use super::導出の結果の定義::導出の欠けの理由;
use super::束縛::束縛;
use super::署名の型の表記の読み方::{署名の型の表記の読み取り, 署名の型の表記を読む};
use super::規則の本体の原子::概念の変数;
use super::評価::{原子の答え, 評価の工程};
use crate::Rustの項目の種類;

impl<解決: 型の名前の解決> 評価の工程<'_, 解決> {
    /// 束縛が当てた関数の署名の型の表記を署名の読み方で読み、名指す型かトレイトのそれぞれをその変数へ当てる。
    pub(super) fn 署名の表記が名指す型を当てる(&self, 束縛: &束縛, 変数: 概念の変数) -> 原子の答え {
        let (表記, 出どころ) = 当てた表記(束縛);
        let mut 答え = 原子の答え::default();
        for 読み取り in 署名の型の表記を読む(&表記.型引数を境界へ読み替えた書かれた文字列()) {
            let (名指したもの, 種類) = match 読み取り {
                署名の型の表記の読み取り::読めない(理由) => {
                    答え.併せる(self.欠けの答え(出どころ, 導出の欠けの理由::関数の署名の型の表記を読めない(理由)));
                    continue;
                }
                署名の型の表記の読み取り::型(型) => (型, Rustの項目の種類::型),
                署名の型の表記の読み取り::トレイト(トレイト) => (トレイト, Rustの項目の種類::トレイト),
            };
            if let Some(型引数名) = 名指したもの.宣言の型引数と一致する名前(表記.有効な型引数名一覧()) {
                答え.併せる(self.欠けの答え(出どころ, 導出の欠けの理由::関数の署名の型引数である { 型引数名 }));
                continue;
            }
            答え.併せる(self.名指した型を当てる(束縛, 変数, &名指したもの, 種類));
        }
        答え
    }
}
