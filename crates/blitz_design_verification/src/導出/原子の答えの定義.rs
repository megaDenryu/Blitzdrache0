//! 規則の本体の原子1つを当てた答えの型。評価の工程(`評価`・`名指す型の読み取り`・`役割の宣言の選び方`)がこの型を組み、束縛と欠けを足していく。
//! 評価の工程の型から分けるのは、答えが評価の工程の借りるもの(宣言・探索の口・規則)を何も持たず、束縛と欠けを蓄える規律だけを持つためである。

use super::導出の結果の定義::導出の欠け;
use super::束縛::束縛;

/// 原子1つを当てた答え。成り立った束縛の一覧と、表記を読めずに落とした箇所の一覧である。
#[derive(Default)]
pub(super) struct 原子の答え {
    束縛一覧: Vec<束縛>,
    欠け一覧: Vec<導出の欠け>,
}

impl 原子の答え {
    /// 成り立った束縛の一覧と欠けの一覧から組む。
    pub(super) fn 生成する(束縛一覧: Vec<束縛>, 欠け一覧: Vec<導出の欠け>) -> Self {
        Self { 束縛一覧, 欠け一覧 }
    }

    /// 欠けを出さずに成り立った束縛の一覧だけから組む。
    pub(super) fn 束縛一覧から生成する(束縛一覧: Vec<束縛>) -> Self {
        Self::生成する(束縛一覧, Vec::new())
    }

    /// 束縛を残さず、欠けを1件だけ持つ答えを組む。
    pub(super) fn 欠け1件から生成する(欠け: 導出の欠け) -> Self {
        Self::生成する(Vec::new(), vec![欠け])
    }

    /// 成り立った束縛を後ろへ足す。
    pub(super) fn 束縛を足す(&mut self, 束縛一覧: impl IntoIterator<Item = 束縛>) {
        self.束縛一覧.extend(束縛一覧);
    }

    /// 表記を読めずに落とした箇所を1件、後ろへ足す。
    pub(super) fn 欠けを足す(&mut self, 欠け: 導出の欠け) {
        self.欠け一覧.push(欠け);
    }

    /// 別の束縛から得た答えを後ろへ併せる。
    pub(super) fn 併せる(&mut self, 他: Self) {
        self.束縛一覧.extend(他.束縛一覧);
        self.欠け一覧.extend(他.欠け一覧);
    }

    /// 表記を読めずに落とした箇所の一覧。
    #[cfg(test)]
    pub(super) fn 欠け一覧(&self) -> &[導出の欠け] {
        &self.欠け一覧
    }

    /// 答えを、成り立った束縛の一覧と欠けの一覧へ分ける。評価の工程が束縛を次の原子へ渡し、欠けを導出の結果へ移すために使う。
    pub(super) fn 束縛一覧と欠け一覧へ分ける(self) -> (Vec<束縛>, Vec<導出の欠け>) {
        (self.束縛一覧, self.欠け一覧)
    }
}
