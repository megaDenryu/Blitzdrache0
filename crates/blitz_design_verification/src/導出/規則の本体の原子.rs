//! 規則の本体の原子とは、定義の式の規則の本体を成す、それ以上分解しない条件のことである。宣言の原子と、型の表記を読む原子と、付いているマーカーを問う原子の3つに分かれる。
//!
//! 宣言の原子はプリミティブな宣言を1件選び、概念の変数を1つと型の表記を1つ当てる。`表記が型を名指す` はその表記を定義の式の読み方で読み、
//! 名指す型を変数へ当てる。この2つを分けるのは、宣言の原子が宣言を選ぶだけで設計の意味を持たず、意味(包みの剥がし方とフレーム型)が
//! 表記を読む原子の側にだけ在るためである。
//! `マーカーが付いている` は、変数に当たった概念に付いているマーカー(上位トレイトの宣言で閉じたもの)がその名前の設計解釈マーカーを含むときだけ束縛を残す。
//! 命令の組を通してコマンドを変換用の素材にする関係の規則(2026-09-28 のオーナー裁定)が、組が `M命令の組` を名乗り、フィールドの型が `Mコマンド` を名乗ることを本体に書くために置いた。
//! 変数は頭の主語と目的語に加えて、頭に現れずに主語と目的語をつなぐ `経由する概念` を持つ。宣言の原子は、既に当たっている変数へ別の概念を当てようとした束縛を落とすため、
//! 2つの宣言を同じ概念でつなぐ(結合する)ことができる。
//! 型の表記を持つ宣言を足すときは、宣言の原子へ選択肢を1つ足し、評価器へその選択肢で宣言を選ぶ枝を足し、規則を足せば足せる。
//! 両端がノードの宣言(処理が処理を呼ぶ等)は、いまの形では書けない。束縛が表記の置き場を1つしか持たず、頭を足す工程が表記の無い束縛で止まるためであり、束縛と結果の拡張が要る。

use super::関数の役割の定義::関数の役割;

/// 規則の頭と本体が名指す概念の変数。頭は主語と目的語の2つを取り、本体は2つの宣言をつなぐために頭に現れない変数を1つ持てる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 概念の変数 {
    /// 頭の関係の主語。
    主語,
    /// 頭の関係の目的語。
    目的語,
    /// 頭に現れず、本体の2つの宣言を同じ概念でつなぐ変数。
    経由する概念,
}

/// 規則の本体を成すプリミティブな原子。宣言の原子は型の表記を1つ当て、`表記が型を名指す` がその表記を読む。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 本体の原子 {
    /// 宣言1件を選び、概念の変数と型の表記を当てる。
    宣言の原子(宣言の原子),
    /// 当てた表記を定義の式の読み方で読み、名指す型を変数へ当てる。
    表記が型を名指す {
        /// 名指す型を当てる変数。
        型: 概念の変数,
    },
    /// 変数に当たった概念に付いているマーカーがその名前の設計解釈マーカーを含むときだけ束縛を残す。
    マーカーが付いている {
        /// 付いているマーカーを問う変数。先の原子が当てている。
        変数: 概念の変数,
        /// 付いているマーカーに含まれることを求める設計解釈マーカーの名前。
        マーカー名: &'static str,
    },
}

impl 本体の原子 {
    /// その変数に当たった概念をこの原子が使うか。宣言の原子はその変数へ宣言の概念を結合し、付いているマーカーの問いはその変数の付いているマーカーを問う。
    /// `表記が型を名指す` は変数へ当てるだけであり、使わない。
    pub(super) fn 変数を使うか(&self, 変数: 概念の変数) -> bool {
        match self {
            Self::宣言の原子(宣言の原子) => 宣言の原子.変数を使うか(変数),
            Self::表記が型を名指す { .. } => false,
            Self::マーカーが付いている { 変数: 問う変数, .. } => *問う変数 == 変数,
        }
    }

    /// 表記を読んで型を当てる原子なら、当てる変数。
    pub(super) const fn 表記から当てる変数(&self) -> Option<概念の変数> {
        match self {
            Self::表記が型を名指す { 型 } => Some(*型),
            Self::宣言の原子(_) | Self::マーカーが付いている { .. } => None,
        }
    }
}

impl 宣言の原子 {
    /// 宣言の概念をその変数へ当てるか。
    fn 変数を使うか(&self, 変数: 概念の変数) -> bool {
        match self {
            Self::フィールドの型の表記を持つ { 持ち主 } => *持ち主 == 変数,
            Self::エンティティの識別子の関連型を持つ { エンティティ } => *エンティティ == 変数,
            Self::役割の型引数を持つ { 処理, .. } => *処理 == 変数,
        }
    }
}

/// プリミティブな宣言を1件選ぶ原子。どれも概念の変数を1つと、型の表記を1つ当てる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 宣言の原子 {
    /// フィールドの型の表記の宣言を1件選び、持ち主を変数へ、フィールドの型を表記へ当てる。
    フィールドの型の表記を持つ {
        /// 持ち主を当てる変数。
        持ち主: 概念の変数,
    },
    /// エンティティの識別子の関連型の宣言を1件選び、エンティティを変数へ、関連型の右辺を表記へ当てる。
    エンティティの識別子の関連型を持つ {
        /// エンティティを当てる変数。
        エンティティ: 概念の変数,
    },
    /// その役割の関数の役割の宣言を1件選び、包んだ関数を変数へ、その位置の型引数を表記へ当てる。
    役割の型引数を持つ {
        /// 選ぶ宣言の役割。
        役割: 関数の役割,
        /// 型引数の位置。0始まりである。
        位置: usize,
        /// 包んだ関数を当てる変数。
        処理: 概念の変数,
    },
}
