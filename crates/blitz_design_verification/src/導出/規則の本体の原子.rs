//! 規則の本体の原子とは、定義の式の規則の本体を成す、それ以上分解しない条件のことである。事実の原子と、型の表記を読む原子の2つに分かれる。
//!
//! 事実の原子はプリミティブな事実を1件選び、概念の変数を1つと型の表記を1つ当てる。`表記が型を名指す` はその表記を定義の式の読み方で読み、
//! 名指す型を変数へ当てる。この2つを分けるのは、事実の原子が事実を選ぶだけで設計の意味を持たず、意味(包みの剥がし方とフレーム型)が
//! 表記を読む原子の側にだけ在るためである。
//! #175 が足す事実のうち、型の表記を持つもの(引数に取る等)は、事実の原子へ選択肢を1つ足し、評価器へその選択肢で事実を選ぶ枝を足し、規則を足せば足せる。
//! 両端が節点の事実(処理が処理を呼ぶ等)と、分類と組み合わせる定義は、いまの形では書けない。束縛が表記の置き場を1つしか持たず、
//! 頭を足す工程が表記の無い束縛で止まり、評価器が分類を読む原子を持たないためであり、束縛・結果・評価器の拡張が要る。

use super::役割::関数の役割;

/// 規則の頭と本体が名指す概念の変数。頭は主語と目的語の2つを取るため、変数も2つである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 概念の変数 {
    /// 頭の関係の主語。
    主語,
    /// 頭の関係の目的語。
    目的語,
}

/// 規則の本体を成すプリミティブな原子。事実の原子は型の表記を1つ当て、`表記が型を名指す` がその表記を読む。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 本体の原子 {
    /// 事実1件を選び、概念の変数と型の表記を当てる。
    事実(事実の原子),
    /// 当てた表記を定義の式の読み方で読み、名指す型を変数へ当てる。
    表記が型を名指す {
        /// 名指す型を当てる変数。
        型: 概念の変数,
    },
}

/// プリミティブな事実を1件選ぶ原子。どれも概念の変数を1つと、型の表記を1つ当てる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 事実の原子 {
    /// フィールドの型の表記の事実を1件選び、持ち主を変数へ、フィールドの型を表記へ当てる。
    フィールドの型の表記を持つ {
        /// 持ち主を当てる変数。
        持ち主: 概念の変数,
    },
    /// エンティティの識別子の関連型の事実を1件選び、エンティティを変数へ、関連型の右辺を表記へ当てる。
    エンティティの識別子の関連型を持つ {
        /// エンティティを当てる変数。
        エンティティ: 概念の変数,
    },
    /// その役割の関数の役割の宣言を1件選び、包んだ関数を変数へ、その位置の型引数を表記へ当てる。
    役割の型引数を持つ {
        /// 選ぶ宣言の役割。
        役割: 関数の役割,
        /// 型引数の位置。0始まりである。
        位置: usize,
        /// 包んだ関数を当てる変数。
        処理: 概念の変数,
    },
    /// その役割の関数の役割の宣言を1件選び、包んだ関数を変数へ、役割の定義が固定で受け取る型の名前を表記へ当てる。
    役割の定義が固定で受け取る {
        /// 選ぶ宣言の役割。
        役割: 関数の役割,
        /// 固定で受け取る型の名前。表記の位置は宣言の行である。
        型名: &'static str,
        /// 包んだ関数を当てる変数。
        処理: 概念の変数,
    },
}
