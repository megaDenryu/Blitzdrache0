//! 型引数の境界とは、関数の署名を書いた場所で有効な型引数1つの名前と、その型引数に課したトレイトの境界の表記の並びのことである。
//! 受け取るのは抽出器が読んだ名前と境界、返すのは、署名の型の表記の中の型引数とその関連型を境界のトレイトへ読み替えた書かれた文字列である。
//!
//! 読み替えるのは、`fn f<口: 世界の形 + ?Sized>(口: &mut 口)` が `fn f(口: &mut (impl 世界の形 + ?Sized))` と同じ意味であるためである。
//! 署名の読み方は `impl トレイト` の引数を境界のトレイトとして読むため、名前を付けた型引数も同じく境界のトレイトとして読む。
//! 型引数の関連型(`口::問い合わせエラー`)も、その関連型を宣言した境界のトレイトとして読む。関連型の具体の型は実装の側が決め、署名はそれを名指さないためである。
//! トレイトの境界を持たない型引数(寿命と `?Sized` だけの境界を含む)は読み替えず、定義の式が読めない表記として数える。

/// 型引数1つの名前と、その型引数に課した境界の表記の並び。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 型引数の境界 {
    名前: String,
    境界の表記一覧: Vec<String>,
}

impl 型引数の境界 {
    /// 型引数の名前と、`+` で並べた境界の表記の並びから組む。
    pub fn 生成する(名前: &str, 境界の表記一覧: Vec<String>) -> Self {
        Self {
            名前: 名前.to_string(), 境界の表記一覧
        }
    }

    // 型引数の代わりに読む `impl` の表記。寿命と `?Sized` でないトレイトの境界を1つも持たないなら無しである。
    fn 読み替えた表記(&self) -> Option<String> {
        let トレイトを持つ = self.境界の表記一覧.iter().any(|境界| !境界.starts_with('\'') && !境界.starts_with('?'));
        トレイトを持つ.then(|| format!("impl {}", self.境界の表記一覧.join(" + ")))
    }
}

/// 書かれた文字列の中の、トレイトの境界を持つ型引数と、その型引数の関連型(`名前::関連型`)を、境界のトレイトの `impl` の表記へ読み替える。
/// 境界の中に別の型引数が現れる(`trait X<T: 甲>: Add<Output = T>` の `Self` の境界の `T`)ときは、置き換える表記の中の型引数も同じ規則で読み替える。
/// 書かれた文字列を1回だけ走査して識別子ごとに境界を引くため、境界一覧の並び順に結果が依存しない。
pub(super) fn 型引数を境界へ読み替える(書かれた文字列: &str, 境界一覧: &[型引数の境界]) -> String {
    途中の名前を除いて読み替える(書かれた文字列, 境界一覧, &[])
}

// 読み替えている途中の型引数の名前を除いて、書かれた文字列の中の型引数と関連型を境界の表記へ読み替える。途中の名前を除くのは、
// 互いを境界に持つ型引数(`T: Into<U>`・`U: From<T>`)で読み替えが終わらなくなるのを止めるためであり、除いた名前は読み替えずに残す。
fn 途中の名前を除いて読み替える(書かれた文字列: &str, 境界一覧: &[型引数の境界], 途中の名前一覧: &[&str]) -> String {
    let 文字一覧: Vec<char> = 書かれた文字列.chars().collect();
    let (mut 置き換えた, mut 位置) = (String::new(), 0);
    while 位置 < 文字一覧.len() {
        let 前が境目 = 位置 == 0 || !識別子の文字か(文字一覧[位置 - 1]);
        let 識別子の長さ = if 前が境目 { 文字一覧[位置..].iter().take_while(|文字| 識別子の文字か(**文字)).count() } else { 0 };
        let 識別子: String = 文字一覧[位置..位置 + 識別子の長さ].iter().collect();
        let 読み替え = 境界一覧
            .iter()
            .filter(|境界| 境界.名前 == 識別子 && !途中の名前一覧.contains(&識別子.as_str()))
            .find_map(|境界| 境界.読み替えた表記().map(|表記| (境界, 表記)));
        match 読み替え {
            Some((境界, 表記)) if 識別子の長さ > 0 => {
                let 途中: Vec<&str> = 途中の名前一覧.iter().copied().chain(std::iter::once(境界.名前.as_str())).collect();
                置き換えた.push_str(&途中の名前を除いて読み替える(&表記, 境界一覧, &途中));
                位置 = 関連型の後ろ(&文字一覧, 位置 + 識別子の長さ);
            }
            _ => {
                置き換えた.extend(&文字一覧[位置..位置 + 識別子の長さ.max(1)]);
                位置 += 識別子の長さ.max(1);
            }
        }
    }
    置き換えた
}

// 名前の後ろが `::識別子` なら、その識別子の後ろの位置。そうでなければ名前の後ろの位置のままである。
fn 関連型の後ろ(文字一覧: &[char], 名前の後ろ: usize) -> usize {
    if 文字一覧.get(名前の後ろ..名前の後ろ + 2) != Some(&[':', ':'][..]) {
        return 名前の後ろ;
    }
    let 識別子の頭 = 名前の後ろ + 2;
    let 識別子の後ろ = 識別子の頭 + 文字一覧[識別子の頭..].iter().take_while(|文字| 識別子の文字か(**文字)).count();
    if 識別子の後ろ == 識別子の頭 { 名前の後ろ } else { 識別子の後ろ }
}

// 識別子を成す文字か。非ASCIIの文字は日本語の識別子の文字として数える。
fn 識別子の文字か(文字: char) -> bool {
    文字.is_ascii_alphanumeric() || 文字 == '_' || !文字.is_ascii()
}
