//! 関数の署名の規則とは、関数の署名の事実からプリミティブな関係(関連関数として持つ・受け手に取る・引数に取る・そのまま受け取る・返す・そのまま返す)を導く定義の式の8本の規則のことである(Issue #175 の第2段階)。
//!
//! **この規則は設計の関係を導かない。** 関数が何を引数に取り何を返すかはコードの形であり、それをそのまま消費する・生成すると読むと、言語の形が設計の意味になり、
//! 設計として説明可能かを問う力を失う(`_doc/設計/設計オントロジー.md` 6.5節)。設計の関係は関数の役割の宣言からだけ導く。
//! 関連関数として持つは、所有者が型の署名とトレイトの署名で2本に分かれる。型の所有者は実装の対象の型の表記を所有者の読み方(包みを剥がさず1つの型を名指す)で読んで名指し、
//! トレイトの所有者は抽出器が節点をそのまま渡すためである。署名の読み方で読むと、`impl トレイト for Vec<Foo>` の関数を `Foo` が持ち、`for (A, B)` の関数を `A` と `B` の両方が持つことになる。
//! 受け手に取るも、所有者が型の署名とトレイトの署名で2本に分かれ、受け手を持つ署名だけを選ぶ。型の所有者は関連関数として持つと同じ所有者の読み方で名指す。
//! 受け手を別の関係にするのは、`self` を受ける関数と受けない関連関数(`生成する` など)を、状態を受けて返す処理の法則が見分けるためである。
//! 引数に取ると返すは、表記を署名の読み方(`署名の表記が型を名指す`)で包みとトレイトの中まで読み、1つの表記が名指す型とトレイトのそれぞれへ関係を1件導く。
//! そのまま受け取るとそのまま返すは、同じ引数と戻り値の表記を、値そのものと `Result`・組・意味型の成分だけまで読む(`署名の読み通す範囲`)。状態を受けて返す処理の宣言の法則が、
//! 状態の値そのものを受けて返す関数と、状態を候補として並べるか順に渡すだけの関数(`&[状態]`・`Vec<状態>`・`impl Iterator<Item = 状態>`・`impl Fn(状態)`)を見分けるためである。
//! 受ける側を返す側と同じ範囲で読むのは、`fn 選ぶ(候補: &[状態]) -> 状態` のように候補の中から1つを選ぶ関数を、状態を受けて返す遷移と数えないためである。
//! 抽出元の構文はどれも関数の署名であり、出どころは `fn` の行である。

use super::定義の式の規則一覧::{導出の規則, 頭の関係};
use super::署名の型の表記の読み方::署名の読み通す範囲;
use super::規則の本体の原子::{事実の原子, 本体の原子, 概念の変数};
use crate::{プリミティブな関係の種類, 抽出元の構文};

/// 関数の署名の規則の8本を組む。
pub(super) fn 関数の署名の規則一覧() -> [導出の規則; 8] {
    let 中まで = 署名の読み通す範囲::包みとトレイトの中まで;
    let 値そのもの = 署名の読み通す範囲::値そのものと成分だけ;
    let 規則 = |名前, 種類, 本体| 導出の規則 {
        名前,
        頭: 頭の関係::プリミティブな関係(種類),
        本体,
        構文: 抽出元の構文::関数の署名,
    };
    [
        規則(
            "関数の所有者の型がその関数を関連関数として持つ",
            プリミティブな関係の種類::関連関数として持つ,
            vec![本体の原子::事実(事実の原子::署名の所有者の型を持つ { 処理: 概念の変数::目的語 }), 本体の原子::所有者の表記が型を名指す { 型: 概念の変数::主語 }],
        ),
        規則(
            "関数を宣言したトレイトがその関数を関連関数として持つ",
            プリミティブな関係の種類::関連関数として持つ,
            vec![本体の原子::事実(事実の原子::署名の所有者のトレイトを持つ {
                処理: 概念の変数::目的語,
                トレイト: 概念の変数::主語,
            })],
        ),
        規則(
            "関数がその実装の対象の型を受け手に取る",
            プリミティブな関係の種類::受け手に取る,
            vec![本体の原子::事実(事実の原子::署名の受け手の型を持つ { 処理: 概念の変数::主語 }), 本体の原子::所有者の表記が型を名指す { 型: 概念の変数::目的語 }],
        ),
        規則(
            "トレイトの本体の関数がそのトレイトを受け手に取る",
            プリミティブな関係の種類::受け手に取る,
            vec![本体の原子::事実(事実の原子::署名の受け手のトレイトを持つ {
                処理: 概念の変数::主語,
                トレイト: 概念の変数::目的語,
            })],
        ),
        規則(
            "関数がその引数の型を引数に取る",
            プリミティブな関係の種類::引数に取る,
            vec![
                本体の原子::事実(事実の原子::署名の引数を持つ { 処理: 概念の変数::主語 }),
                本体の原子::署名の表記が型を名指す {
                    型: 概念の変数::目的語, 範囲: 中まで
                },
            ],
        ),
        規則(
            "関数がその引数の型の値をそのまま受け取る",
            プリミティブな関係の種類::そのまま受け取る,
            vec![
                本体の原子::事実(事実の原子::署名の引数を持つ { 処理: 概念の変数::主語 }),
                本体の原子::署名の表記が型を名指す {
                    型: 概念の変数::目的語, 範囲: 値そのもの
                },
            ],
        ),
        規則(
            "関数がその戻り値の型を返す",
            プリミティブな関係の種類::返す,
            vec![
                本体の原子::事実(事実の原子::署名の戻り値を持つ { 処理: 概念の変数::主語 }),
                本体の原子::署名の表記が型を名指す {
                    型: 概念の変数::目的語, 範囲: 中まで
                },
            ],
        ),
        規則(
            "関数がその戻り値の型をそのまま返す",
            プリミティブな関係の種類::そのまま返す,
            vec![
                本体の原子::事実(事実の原子::署名の戻り値を持つ { 処理: 概念の変数::主語 }),
                本体の原子::署名の表記が型を名指す {
                    型: 概念の変数::目的語, 範囲: 値そのもの
                },
            ],
        ),
    ]
}
