//! 型引数の境界の読み替えの試験。トレイトの境界を持つ型引数とその関連型だけを境界のトレイトの `impl` へ読み替え、
//! 境界を持たない型引数と、同じ文字で始まる別の識別子を読み替えないことを固定する。

use super::型引数の境界の定義::{型引数の境界, 型引数を境界へ読み替える};

fn 口の境界() -> 型引数の境界 {
    型引数の境界::生成する("口", vec!["世界の形を尋ねる口".to_string(), "?Sized".to_string()])
}

#[test]
fn 境界を持つ型引数と関連型を境界のトレイトへ読み替える() {
    let 読み替えた = 型引数を境界へ読み替える("Result<掃引の答え, 口::問い合わせエラー>", &[口の境界()]);
    assert_eq!(読み替えた, "Result<掃引の答え, impl 世界の形を尋ねる口 + ?Sized>");
    assert_eq!(型引数を境界へ読み替える("&mut 口", &[口の境界()]), "&mut impl 世界の形を尋ねる口 + ?Sized");
}

#[test]
fn 同じ文字で始まる別の識別子は読み替えない() {
    assert_eq!(型引数を境界へ読み替える("口の実装を代表する口", &[口の境界()]), "口の実装を代表する口");
    assert_eq!(型引数を境界へ読み替える("入口", &[口の境界()]), "入口");
}

#[test]
fn トレイトの境界を持たない型引数は読み替えない() {
    let 寿命だけ = 型引数の境界::生成する("T", vec!["'a".to_string(), "?Sized".to_string()]);
    let 境界無し = 型引数の境界::生成する("U", Vec::new());
    assert_eq!(型引数を境界へ読み替える("(T, U)", &[寿命だけ, 境界無し]), "(T, U)");
}

// 反証: 境界を並び順に1回ずつ置き換えると、`Self` の境界を最後に積んだ `trait X<T: 甲>: Add<Output = T>` で、`Self` を置き換えた表記に生の `T` が残る。
#[test]
fn 境界の中の別の型引数も並び順に依らず読み替える() {
    let 甲の境界 = 型引数の境界::生成する("T", vec!["甲".to_string()]);
    let 自分の境界 = 型引数の境界::生成する("Self", vec!["X".to_string(), "Add<Output = T>".to_string()]);
    let 期待 = "impl X + Add<Output = impl 甲>";
    assert_eq!(型引数を境界へ読み替える("Self", &[甲の境界.clone(), 自分の境界.clone()]), 期待);
    assert_eq!(型引数を境界へ読み替える("Self", &[自分の境界, 甲の境界]), 期待);
}

// 互いを境界に持つ型引数は、読み替えている途中の名前を読み替えずに残して止まる。
#[test]
fn 互いを境界に持つ型引数の読み替えは止まる() {
    let 前 = 型引数の境界::生成する("T", vec!["Into<U>".to_string()]);
    let 後 = 型引数の境界::生成する("U", vec!["From<T>".to_string()]);
    assert_eq!(型引数を境界へ読み替える("T", &[前, 後]), "impl Into<impl From<T>>");
}
