//! 署名の型の表記のうち、包みも組も関数の型も剥がし終えた名前1つ(型引数を持つフレーム型を含む)と、`impl`・`dyn` の境界のトレイトの名前を読む工程。
//! 依存を持たない純粋な関数だけを置く。受け取るのは名前の表記、返すのは名指す型かトレイトか読めない理由である。
//!
//! パスの修飾が付いた名前(`fmt::Result`・`crate::a::型`)は、修飾と最後の名前に分けて `修飾された名前` として答える。修飾を落として名前だけで定義を探すと
//! 同じ名前の別の定義へ当たりうるため、修飾がどのモジュールを指すかは評価器が解決の口へ問い(`use` の取り込みを読む)、ここでは決めない。
//! フレーム型(`変位<ワールド>`)の座標系の引数に付いた修飾(`blitz_math::ワールド`)は落とし、名前だけで読む。座標系は `blitz_math` の幻影型であり、
//! 節点の同一性は座標系を名前で持つため、修飾の無い表記と同じ節点を名指すためである。
//! 型引数を持つ名前のうちフレーム型でないものは、修飾の有無によらず読めない(フィールドの読み方と同じく、内側の型への関係を表せない)。

use super::super::型の表記の読み方::{型の表記の読み取り, 型の表記を読む};
use super::super::型の表記を読めない理由の定義::型の表記を読めない理由;
use super::super::表記が名指す型の定義::{フレーム型, 先頭の識別子, 表記が名指す型};
use super::{型引数を分ける, 最上位で分ける, 署名の型の表記の読み取り};
use crate::Rustの項目の種類;

/// 名前1つの表記を、その種類(型かトレイト)の名指したものとして読む。
pub(super) fn 名前を読む(芯: &str, 種類: Rustの項目の種類) -> Vec<署名の型の表記の読み取り> {
    let (前, 型引数) = 型引数を分ける(芯).map_or((芯, None), |(前, 型引数)| (前, Some(型引数)));
    let (修飾, 最後の名前) = match 前.rsplit_once("::") {
        Some((修飾, 名前)) => (Some(修飾.trim()), 名前.trim()),
        None => (None, 前.trim()),
    };
    let 読めない = |理由: fn(String) -> 型の表記を読めない理由| vec![署名の型の表記の読み取り::読めない(理由(芯.to_string()))];
    let 名指したもの = match (フレーム型::名前から探す(最後の名前), 型引数, 修飾) {
        (Some(型), Some(型引数), _) => match 表記が名指す型::フレーム型として読む(型, &座標系の修飾を落とす(型引数)) {
            Some(名指す型) => 名指す型,
            None => return 読めない(|表記| 型の表記を読めない理由::フレーム型の型引数が座標系の名前の並びでない { 表記 }),
        },
        (_, Some(_), Some(_)) => return 読めない(|表記| 型の表記を読めない理由::型の表記が剥がす包みでないジェネリクスである { 表記 }),
        (_, _, None) => return 修飾の無い名前を読む(芯, 種類),
        (_, None, Some(_)) if 最後の名前.is_empty() || 先頭の識別子(最後の名前) != 最後の名前 => {
            return 読めない(|表記| 型の表記を読めない理由::型の表記がRustのパスでない { 表記 });
        }
        (_, None, Some(_)) => 表記が名指す型::名前から生成する(最後の名前),
    };
    vec![match 修飾 {
        Some(修飾) => 署名の型の表記の読み取り::修飾された名前 {
            修飾: 修飾.to_string(),
            名前: 名指したもの,
            種類,
        },
        None => 修飾の無い読み取り(名指したもの, 種類),
    }]
}

/// `impl`・`dyn` の境界のトレイトの名前を読む。型引数は呼び出し側が分けて読み済みである。
pub(super) fn 境界のトレイトの名前を読む(トレイト: &str) -> Vec<署名の型の表記の読み取り> {
    名前を読む(トレイト, Rustの項目の種類::トレイト)
}

// 修飾の無い名前を、フィールドの読み方で読む。プリミティブと値を持たない型は何も名指さない。
fn 修飾の無い名前を読む(芯: &str, 種類: Rustの項目の種類) -> Vec<署名の型の表記の読み取り> {
    match 型の表記を読む(芯) {
        型の表記の読み取り::設計概念である(型) => vec![修飾の無い読み取り(型, 種類)],
        型の表記の読み取り::プリミティブである | 型の表記の読み取り::値を持たない型である => Vec::new(),
        型の表記の読み取り::保証範囲の外(理由) => vec![署名の型の表記の読み取り::読めない(理由)],
    }
}

// 修飾の無い名指したものを、種類に応じた読み取りにする。
fn 修飾の無い読み取り(名指したもの: 表記が名指す型, 種類: Rustの項目の種類) -> 署名の型の表記の読み取り {
    match 種類 {
        Rustの項目の種類::トレイト => 署名の型の表記の読み取り::トレイト(名指したもの),
        Rustの項目の種類::型 | Rustの項目の種類::処理 => 署名の型の表記の読み取り::型(名指したもの),
    }
}

// 座標系の引数の並びから、それぞれのパスの修飾を落として `, ` でつなぐ。
fn 座標系の修飾を落とす(型引数の並び: &str) -> String {
    最上位で分ける(型引数の並び, ',').into_iter().map(|座標系| 座標系.rsplit("::").next().unwrap_or_default().trim()).collect::<Vec<_>>().join(", ")
}
