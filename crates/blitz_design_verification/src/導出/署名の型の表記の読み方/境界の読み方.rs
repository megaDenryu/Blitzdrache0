//! `impl トレイト`・`dyn トレイト` の境界1つを読む工程。受け取るのは `+` で分けた境界1つ、返すのはそのトレイトと、トレイトの型の引数と関連型の指定が名指す型の並びである。
//! 依存を持たない純粋な関数だけを置く。寿命(`'a`)と `?Sized` は何も名指さない。標準ライブラリのトレイトは設計概念にせず、型の引数だけを読む。
//! クロージャのトレイト(`Fn(A) -> B`)は標準のトレイトであり、引数と戻り値の型だけを読む(`関数の型の読み方`)。

use super::名前の読み方::境界のトレイトの名前を読む;
use super::読み通す型と標準の型の見分け::標準ライブラリの型か;
use super::関数の型の読み方::{クロージャのトレイトの引数と戻り値, 関数の型の中を読む};
use super::{型引数を分ける, 最上位で分ける, 署名の型の表記の読み取り, 署名の型の表記を読む, 署名の読み通す範囲};

/// `impl`・`dyn` の境界1つから、そのトレイトと、トレイトの型の引数と関連型の指定が名指す型を読む。
pub(super) fn 境界のトレイトを読む(境界: &str) -> Vec<署名の型の表記の読み取り> {
    let 境界 = 境界.trim();
    if 境界.is_empty() || 境界.starts_with('\'') || 境界.starts_with('?') {
        return Vec::new();
    }
    if let Some((引数の並び, 戻り値)) = クロージャのトレイトの引数と戻り値(境界) {
        return 関数の型の中を読む(引数の並び, 戻り値);
    }
    let (トレイト, 引数の読み取り一覧): (&str, Vec<署名の型の表記の読み取り>) = match 型引数を分ける(境界) {
        Some((前, 型引数)) => (
            前.trim(),
            最上位で分ける(型引数, ',')
                .into_iter()
                .flat_map(|引数| 署名の型の表記を読む(関連型の指定なら型の側(引数), 署名の読み通す範囲::包みとトレイトの中まで))
                .collect(),
        ),
        None => (境界, Vec::new()),
    };
    if 標準ライブラリの型か(トレイト) {
        return 引数の読み取り一覧;
    }
    境界のトレイトの名前を読む(トレイト).into_iter().chain(引数の読み取り一覧).collect()
}

// トレイトの型の引数1つが関連型の指定(`Item = T`)なら、指定した型の側 `T`。そうでなければ引数のままである。
fn 関連型の指定なら型の側(引数: &str) -> &str {
    match 最上位で分ける(引数, '=').as_slice() {
        [名前, 型] if !名前.contains(['<', '(']) => 型,
        _ => 引数,
    }
}
