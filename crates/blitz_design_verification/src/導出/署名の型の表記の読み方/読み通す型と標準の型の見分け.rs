//! 署名の読み方が中身を読み通す型と、設計概念として名指さない標準ライブラリの型の見分け。依存を持たない純粋な関数だけを置く。
//! 受け取るのは型の表記の書かれた文字列の一部、返すのはその見分けである。
//!
//! 中身を読み通す型とは、関数の戻り値の形を決めるだけで、それ自身は関数が扱う型を名指さない型のことである。標準の `Result` と、
//! `blitz_design` の意味型(`遷移成功結果`・`遷移失敗結果`・`問い合わせを伴う遷移成功結果`)と、問い合わせを伴う遷移の戻り値の別名
//! (`問い合わせを伴う遷移の結果`)がこれに当たる。`Result<遷移成功結果<状態, 出来事>, 遷移失敗結果<状態, 失敗>>` を返す関数が返すのは、状態と出来事と失敗である。
//! 意味型の名前は修飾の無い名前か `blitz_design::` で修飾した名前だけを受け取る。ドメインが同じ名前の型を定義すると取り違えるが、`Result` と同じくこの近似を受け入れる。
//!
//! 標準ライブラリの型とは、`std::`・`core::`・`alloc::` で修飾した表記のうち、型の引数を持たないもの(寿命だけを持つものを含む)のことである。
//! 設計概念にしないのは、プリミティブと同じくこのリポジトリの設計の概念でないためであり、外す条件をこの形で書き下せるためである。
//! 型の引数を持つ標準の型(`std::collections::HashMap<K, V>` など)は外さない。外すと中身の型への関係まで黙って落とすためである。
//! 寿命だけの型引数(`Formatter<'_>`・`経路Ref<'_>`)は型を名指さないため、型の引数を落として型の名前だけを読む。
//! 値を1つだけ必ず持つ包み(`Box`・`Arc`)は、`そのまま返す` の読み方が中身を値そのものとして読む包みである。`Vec`・`Option`・`BTreeSet` は0個か複数の値を持ち、中身の値そのものを返さない。

/// `Result` の包みとして受け取る書かれた文字列。
const 結果の包みの表記一覧: [&str; 3] = ["Result", "std::result::Result", "core::result::Result"];

/// 中身を読み通す `blitz_design` の意味型と戻り値の別名の名前。
const 読み通す意味型の名前一覧: [&str; 4] = ["遷移成功結果", "遷移失敗結果", "問い合わせを伴う遷移成功結果", "問い合わせを伴う遷移の結果"];

/// 値を1つだけ必ず持つ包みの名前。パスの最後の名前で照らす。剥がす包みか(`型の表記の読み方`)を先に確かめた表記にだけ問う。
const 値を1つだけ持つ包みの名前一覧: [&str; 2] = ["Box", "Arc"];

/// 標準ライブラリの型の修飾の頭。
const 標準ライブラリの修飾一覧: [&str; 3] = ["std::", "core::", "alloc::"];

/// 型引数の前の表記が、中身を読み通す型(`Result` か意味型)か。
pub(super) fn 中身を読み通す型か(前: &str) -> bool {
    let 前 = 前.trim();
    結果の包みの表記一覧.contains(&前) || 読み通す意味型の名前一覧.contains(&前.strip_prefix("blitz_design::").unwrap_or(前))
}

/// 剥がす包みの型引数の前の表記が、値を1つだけ必ず持つ包みか。
pub(super) fn 値を1つだけ持つ包みか(前: &str) -> bool {
    値を1つだけ持つ包みの名前一覧.contains(&前.rsplit("::").next().unwrap_or_default().trim())
}

/// 型引数の並びが寿命だけか(`'_`・`'a, 'b`)。空の並びは寿命だけと数えない。
pub(super) fn 寿命だけの型引数か(型引数の並び: &str) -> bool {
    let 一覧: Vec<&str> = 型引数の並び.split(',').map(str::trim).collect();
    !一覧.is_empty() && 一覧.iter().all(|引数| 引数.starts_with('\'') && 引数.len() > 1)
}

/// 表記が、型の引数を持たない標準ライブラリの型か。
pub(super) fn 標準ライブラリの型か(表記: &str) -> bool {
    let 表記 = 表記.trim();
    !表記.contains('<') && 標準ライブラリの修飾一覧.iter().any(|修飾| 表記.starts_with(修飾))
}
