//! 関数を値として受け渡す型の表記(関数ポインタ `fn(A, B) -> C` とクロージャのトレイト `Fn(A) -> B`・`FnMut`・`FnOnce`)を、引数の並びと戻り値の型に分ける工程。
//! 依存を持たない純粋な関数だけを置く。受け取るのは表記、返すのは丸括弧の内側と矢印の後ろの組と、それらを署名の読み方で読んだ並びである。
//!
//! 関数の型そのものは設計概念を名指さない。関数ポインタは言語の型であり、クロージャのトレイトは標準のトレイトだからである。
//! その引数と戻り値の型は、関数の署名の型の表記に書かれた型であり、`Iterator<Item = T>` の `T` と同じく `引数に取る`・`返す` の「型の表記に書いている」に当たる。
//! そのため署名の読み方は、関数の型を読めない表記とせず、引数と戻り値の型を読む。

use super::{最上位で分ける, 署名の型の表記の読み取り, 署名の型の表記を読む, 署名の読み通す範囲};

/// クロージャのトレイトの名前。パスの最後の名前で照らす(`std::ops::Fn` も当たる)。
const クロージャのトレイトの名前一覧: [&str; 3] = ["Fn", "FnMut", "FnOnce"];

/// 関数ポインタの表記(`fn(A) -> B`・`unsafe fn(A)`)なら、引数の並びと戻り値の型。
pub(super) fn 関数ポインタの引数と戻り値(表記: &str) -> Option<(&str, Option<&str>)> {
    let 残り = 表記.strip_prefix("unsafe ").map_or(表記, str::trim_start);
    丸括弧の中と戻り値に分ける(残り.strip_prefix("fn")?.trim_start())
}

/// クロージャのトレイトの境界(`Fn(A) -> B`・`std::ops::FnMut(A)`)なら、引数の並びと戻り値の型。
pub(super) fn クロージャのトレイトの引数と戻り値(境界: &str) -> Option<(&str, Option<&str>)> {
    let (名前, 残り) = 境界.split_at(境界.find('(')?);
    let クロージャのトレイトか = クロージャのトレイトの名前一覧.contains(&名前.rsplit("::").next().unwrap_or_default().trim());
    if !クロージャのトレイトか {
        return None;
    }
    丸括弧の中と戻り値に分ける(残り)
}

// 先頭の `(` と対応する `)` の内側と、その後ろの `->` より後ろの戻り値の型。`->` が無ければ戻り値は無しである。
fn 丸括弧の中と戻り値に分ける(表記: &str) -> Option<(&str, Option<&str>)> {
    表記.strip_prefix('(')?;
    let (mut 深さ, mut 直前) = (0usize, ' ');
    for (位置, 文字) in 表記.char_indices() {
        match 文字 {
            '(' | '[' | '<' => 深さ += 1,
            '>' if 直前 == '-' => {}
            ')' | ']' | '>' => 深さ = 深さ.saturating_sub(1),
            _ => {}
        }
        直前 = 文字;
        if 文字 == ')' && 深さ == 0 {
            let 戻り値 = 表記[位置 + 1..].trim().strip_prefix("->").map(str::trim);
            return Some((&表記[1..位置], 戻り値));
        }
    }
    None
}

/// 関数の型の引数の並びと戻り値の型を、包みとトレイトの中まで読む。
pub(super) fn 関数の型の中を読む(引数の並び: &str, 戻り値: Option<&str>) -> Vec<署名の型の表記の読み取り> {
    let 範囲 = 署名の読み通す範囲::包みとトレイトの中まで;
    最上位で分ける(引数の並び, ',').into_iter().chain(戻り値).flat_map(|型| 署名の型の表記を読む(型, 範囲)).collect()
}
