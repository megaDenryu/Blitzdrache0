//! 型の表記を読めない理由とは、定義の式が型の表記を剥がして名指す型を求めようとして、その綴りを読めなかった理由のことである。
//!
//! 読めない綴りを黙って読み飛ばさずに理由として返すのは、検査器が解析できなかった入力を黙って対象から外してはならないためである
//! (`.claude/global-reference/全プロジェクト共通CLAUDE.md`「検査器は解析できなかった入力を黙って対象から外してはならない」)。
//! 抽出器はこの理由を自分の保証範囲の外の構文の1つとして数え、`cargo xtask conform` はそれを違反として報告する。
//! 種別の呼び名と説明の文言は、段階2(Issue #193)の前に抽出器が持っていた文言と同じである。

/// 型の表記を読めない理由。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 型の表記を読めない理由 {
    /// 参照と包みを落とした後もRustのパスとして読めない(配列・タプル・関数ポインタ・`impl`・`dyn`・生ポインタ)。
    型の表記がRustのパスでない {
        /// 読めなかった綴り。
        表記: String,
    },
    /// 剥がしてよい包みでもフレーム型の一覧の型でもないジェネリクスであり、内側の型への関係を表せない。
    型の表記が剥がす包みでないジェネリクスである {
        /// 読めなかった綴り。
        表記: String,
    },
    /// フレーム型の一覧の型でありながら、型引数が座標系の名前だけの並びでないか、数がその型の座標系の数と合わない。
    フレーム型の型引数が座標系の名前の並びでない {
        /// 読めなかった綴り。
        表記: String,
    },
    /// パスの修飾があり、修飾を落として名前で解決すると別の定義へ当たりうる。
    型の表記にパスの修飾がある {
        /// 読めなかった綴り。
        表記: String,
    },
}

impl 型の表記を読めない理由 {
    /// 選択肢の種別の呼び名。運ぶ綴りを含めないのは、この呼び名が同じ種別をまとめた件数の見出しになるためである。
    pub const fn 種別の呼び名(&self) -> &'static str {
        match self {
            Self::型の表記がRustのパスでない { .. } => "型の表記がRustのパスでない",
            Self::型の表記が剥がす包みでないジェネリクスである { .. } => "型の表記が剥がす包みでないジェネリクスである",
            Self::フレーム型の型引数が座標系の名前の並びでない { .. } => "フレーム型の型引数が座標系の名前の並びでない",
            Self::型の表記にパスの修飾がある { .. } => "型の表記にパスの修飾がある",
        }
    }

    /// 人が読む説明。
    pub fn 説明(&self) -> String {
        match self {
            Self::型の表記がRustのパスでない { 表記 } => format!("型の表記 `{表記}` が参照と包みを落とした後もRustのパスとして読めない"),
            Self::型の表記が剥がす包みでないジェネリクスである { 表記 } => {
                format!("型の表記 `{表記}` が `Vec`・`Option`・`Box`・`BTreeSet` でもフレーム型の一覧の型でもないジェネリクスであり内側の型への関係を表せない")
            }
            Self::フレーム型の型引数が座標系の名前の並びでない { 表記 } => format!("型の表記 `{表記}` がフレーム型でありながら、型引数が座標系の名前だけの並びでないか座標系の数が合わない"),
            Self::型の表記にパスの修飾がある { 表記 } => format!("型の表記 `{表記}` にパスの修飾があり、修飾を落として名前で解決すると別の定義へ当たりうる"),
        }
    }
}
