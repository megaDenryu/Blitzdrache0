//! 定義の式をプリミティブな事実の上で評価する工程。受け取るのは事実と分類の事実と型の名前の解決の口、返すのは導出の結果である。
//! 分類の事実は、上位トレイトの宣言で閉じた節点の分類へ組んでから `分類にマーカーを持つ` の原子が読む。分類は関係の辺ではなく、関係を導く条件としてだけ読む。
//!
//! 規則ごとに、空の束縛1つから始めて本体の原子を左から当て、残った束縛ごとに頭の関係を1件導く。規則の順と事実の順を保つため、
//! 導いた関係の並びは入力の並びから一意に決まる。同じ表記を2つの規則が読めば、読めなかった欠けも2件になる。
//! 欠けを重ねて数えるのは、段階2の前の抽出器が型引数の位置ごとに表記を読み、同じ数の欠けを出していたためである。
//! 型の表記を読む原子(`表記が型を名指す`)の評価は `名指す型の読み取り` が、役割の型引数を選ぶ事実の原子の評価は `役割の宣言の事実の選び方` が、
//! 頭の関係を導出の結果へ足す操作は `導出の結果の定義` が持つ。

use super::プリミティブな事実の定義::プリミティブな事実;
use super::型の名前の解決の定義::型の名前の解決;
use super::定義の式の規則一覧::{定義の式, 導出の規則};
use super::導出の結果の定義::{導出の欠け, 導出の結果};
use super::束縛::束縛;
use super::規則の本体の原子::{事実の原子, 本体の原子, 概念の変数};
use crate::{分類の事実, 節点の分類};

/// 原子1つを当てた答え。成り立った束縛の一覧と、表記を読めずに落とした箇所の一覧である。
#[derive(Default)]
pub(super) struct 原子の答え {
    pub(super) 束縛一覧: Vec<束縛>,
    pub(super) 欠け一覧: Vec<導出の欠け>,
}

/// 事実と節点の分類と解決の口と当てている規則を借りて、規則1つの本体の原子を当てる工程。規則ごとに組み、欠けへその規則の頭の関係を書く。
/// 規則の本体まで借りるのは、定義をたどれなかった型を当てた変数がその規則の中でどう使われるかを、欠けへ書くためである。
pub(super) struct 評価の工程<'a, 解決: 型の名前の解決> {
    pub(super) 事実: &'a プリミティブな事実,
    pub(super) 分類: &'a 節点の分類,
    pub(super) 解決: &'a 解決,
    pub(super) 規則: &'a 導出の規則,
}

impl 定義の式 {
    /// 全ての規則をその事実の上で評価する。型の表記を書いた場所から型の定義をたどるときは、渡された解決の口へ問い、概念の分類は分類の事実を閉じて問う。
    pub fn 評価する(&self, 事実: &プリミティブな事実, 分類の事実: &分類の事実, 解決: &impl 型の名前の解決) -> 導出の結果 {
        let 分類 = 節点の分類::事実から閉包を取って生成する(分類の事実.clone());
        let mut 結果 = 導出の結果::default();
        for 規則 in self.規則一覧() {
            let 工程 = 評価の工程 { 事実, 分類: &分類, 解決, 規則 };
            let mut 束縛一覧 = vec![束縛::空()];
            for 原子 in &規則.本体 {
                let 答え = 工程.原子を当てる(*原子, &束縛一覧);
                結果.欠け一覧.extend(答え.欠け一覧);
                束縛一覧 = 答え.束縛一覧;
            }
            for 束縛 in &束縛一覧 {
                結果.規則の頭を足す(規則, 束縛);
            }
        }
        結果
    }
}

impl 原子の答え {
    /// 別の束縛から得た答えを後ろへ併せる。
    pub(super) fn 併せる(&mut self, 他: Self) {
        self.束縛一覧.extend(他.束縛一覧);
        self.欠け一覧.extend(他.欠け一覧);
    }
}

impl<解決: 型の名前の解決> 評価の工程<'_, 解決> {
    // 原子1つを、いまの束縛の全部へ当てる。
    fn 原子を当てる(&self, 原子: 本体の原子, 束縛一覧: &[束縛]) -> 原子の答え {
        let mut 答え = 原子の答え::default();
        for 束縛 in 束縛一覧 {
            答え.併せる(match 原子 {
                本体の原子::事実(事実の原子) => self.事実の原子を当てる(事実の原子, 束縛),
                本体の原子::表記が型を名指す { 型 } => self.名指す型を当てる(束縛, 型),
                本体の原子::所有者の表記が型を名指す { 型 } => self.所有者の型を当てる(束縛, 型),
                本体の原子::署名の表記が型を名指す { 型 } => self.署名の表記が名指す型を当てる(束縛, 型),
                本体の原子::分類にマーカーを持つ { 変数, マーカー名 } => self.分類にマーカーを持つ束縛だけを残す(束縛, 変数, マーカー名),
            });
        }
        答え
    }

    // 事実の原子を1つの束縛へ当て、事実の候補ごとに分かれた束縛と、表記を当てられなかった欠けを返す。
    fn 事実の原子を当てる(&self, 原子: 事実の原子, 束縛: &束縛) -> 原子の答え {
        let 事実 = self.事実;
        let 束縛一覧 = match 原子 {
            事実の原子::フィールドの型の表記を持つ { 持ち主 } => 事実.フィールドの型の表記一覧.iter().filter_map(|件| 束縛.事実から当てる(持ち主, 件.持ち主.clone(), 件.表記.clone(), &件.出どころ)).collect(),
            事実の原子::エンティティの識別子の関連型を持つ { エンティティ } => 事実
                .エンティティの識別子の関連型一覧
                .iter()
                .filter_map(|件| 束縛.事実から当てる(エンティティ, 件.エンティティ.clone(), 件.表記.clone(), &件.出どころ))
                .collect(),
            事実の原子::役割の型引数を持つ { 役割, 位置, 処理 } => return self.役割の型引数を当てる(役割, 位置, 処理, 束縛),
            事実の原子::署名の所有者の型を持つ { .. }
            | 事実の原子::署名の所有者のトレイトを持つ { .. }
            | 事実の原子::署名の受け手の型を持つ { .. }
            | 事実の原子::署名の受け手のトレイトを持つ { .. }
            | 事実の原子::署名の引数を持つ { .. }
            | 事実の原子::署名の戻り値を持つ { .. } => 事実.関数の署名一覧.iter().flat_map(|署名| 署名.原子で当てた束縛一覧(原子, 束縛)).collect(),
        };
        原子の答え { 束縛一覧, 欠け一覧: Vec::new() }
    }

    // 変数に当たった概念の分類がその名前のマーカーを含むなら束縛をそのまま残し、含まなければ落とす。分類を問うだけであり、表記を読まないため欠けを出さない。
    // 変数に何も当たっていなければ、規則が分類を問う変数を先の原子に当てさせるという不変条件が破れている。
    fn 分類にマーカーを持つ束縛だけを残す(&self, 束縛: &束縛, 変数: 概念の変数, マーカー名: &str) -> 原子の答え {
        let Some(概念) = 束縛.当たっている概念(変数) else {
            panic!("`分類にマーカーを持つ` が何も当たっていない変数 {変数:?} の分類を問うた: 定義の式の規則は分類を問う変数を先の原子に当てさせるという不変条件が破れた");
        };
        let 含むか = self.分類.概念の分類(概念).iter().any(|トレイト| トレイト.識別子().名前 == マーカー名);
        原子の答え {
            束縛一覧: if 含むか { vec![束縛.clone()] } else { Vec::new() },
            欠け一覧: Vec::new(),
        }
    }
}
