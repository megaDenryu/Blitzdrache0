//! 定義の式をプリミティブな宣言の上で評価する工程。受け取るのは宣言と設計解釈マーカーの宣言の一覧と型の名前の定義の探索の口、返すのは導出の結果である。
//! 設計解釈マーカーの宣言の一覧は、上位トレイトの宣言で閉じた各型に付いているマーカーの一覧へ組んでから `マーカーが付いている` の原子が読む。付いているマーカーは関係のエッジではなく、関係を導く条件としてだけ読む。
//!
//! 規則ごとに、空の束縛1つから始めて本体の原子を左から当て、残った束縛ごとに頭の関係を1件導く。規則の順と宣言の順を保つため、
//! 導いた関係の並びは入力の並びから一意に決まる。同じ表記を2つの規則が読めば、読めなかった欠けも2件になる。
//! 欠けを重ねて数えるのは、段階2の前の抽出器が型引数の位置ごとに表記を読み、同じ数の欠けを出していたためである。
//! 型の表記を読む原子(`表記が型を名指す`)の評価は `名指す型の読み取り` が、役割の型引数を選ぶ宣言の原子の評価は `役割の宣言の選び方` が、
//! 頭の関係を導出の結果へ足す操作は `導出の結果の定義` が、原子1つを当てた答えの型は `原子の答えの定義` が持つ。

use super::プリミティブな宣言の定義::プリミティブな宣言;
use super::原子の答えの定義::原子の答え;
use super::型の名前の定義の探索の定義::型の名前の定義の探索;
use super::定義の式の規則一覧::{定義の式, 導出の規則};
use super::導出の結果の定義::導出の結果;
use super::束縛::束縛;
use super::規則の本体の原子::{宣言の原子, 本体の原子, 概念の変数};
use crate::{各型に付いているマーカーの一覧, 設計解釈マーカーの宣言の一覧};

/// 宣言と各型に付いているマーカーの一覧と定義の探索の口と当てている規則を借りて、規則1つの本体の原子を当てる工程。規則ごとに組み、欠けへその規則の頭の関係を書く。
/// 規則の本体まで借りるのは、定義をたどれなかった型を当てた変数がその規則の中でどう使われるかを、欠けへ書くためである。
pub(super) struct 評価の工程<'a, 探索: 型の名前の定義の探索> {
    プリミティブな宣言: &'a プリミティブな宣言,
    各型に付いているマーカーの一覧: &'a 各型に付いているマーカーの一覧,
    探索: &'a 探索,
    規則: &'a 導出の規則,
}

impl 定義の式 {
    /// 全ての規則をその宣言の上で評価する。型の表記を書いた場所から型の定義をたどるときは、渡された定義の探索の口へ問い、概念に付いているマーカーは設計解釈マーカーの宣言の一覧を閉じて問う。
    pub fn 評価する(&self, プリミティブな宣言: &プリミティブな宣言, 設計解釈マーカーの宣言の一覧: &設計解釈マーカーの宣言の一覧, 探索: &impl 型の名前の定義の探索) -> 導出の結果 {
        let 各型に付いているマーカーの一覧 = 各型に付いているマーカーの一覧::設計解釈マーカーの宣言の一覧から閉包を取って生成する(設計解釈マーカーの宣言の一覧.clone());
        let mut 結果 = 導出の結果::default();
        for 規則 in self.規則一覧() {
            let 工程 = 評価の工程::生成する(プリミティブな宣言, &各型に付いているマーカーの一覧, 探索, 規則);
            let mut 束縛一覧 = vec![束縛::空()];
            for 原子 in 規則.本体() {
                let (成り立った束縛一覧, 欠け一覧) = 工程.原子を当てる(*原子, &束縛一覧).束縛一覧と欠け一覧へ分ける();
                結果.欠け一覧を足す(欠け一覧);
                束縛一覧 = 成り立った束縛一覧;
            }
            for 束縛 in &束縛一覧 {
                結果.規則の頭を足す(規則, 束縛);
            }
        }
        結果
    }
}

impl<'a, 探索: 型の名前の定義の探索> 評価の工程<'a, 探索> {
    /// 宣言と各型に付いているマーカーの一覧と定義の探索の口と当てる規則を借りて組む。
    pub(super) fn 生成する(プリミティブな宣言: &'a プリミティブな宣言, 各型に付いているマーカーの一覧: &'a 各型に付いているマーカーの一覧, 探索: &'a 探索, 規則: &'a 導出の規則) -> Self {
        Self {
            プリミティブな宣言,
            各型に付いているマーカーの一覧,
            探索,
            規則,
        }
    }

    /// 原子を当てる宣言。
    pub(super) fn プリミティブな宣言(&self) -> &'a プリミティブな宣言 {
        self.プリミティブな宣言
    }

    /// 型の名前の定義の探索の口。
    pub(super) fn 探索(&self) -> &'a 探索 {
        self.探索
    }

    /// いま本体の原子を当てている規則。
    pub(super) fn 規則(&self) -> &'a 導出の規則 {
        self.規則
    }
}

impl<探索: 型の名前の定義の探索> 評価の工程<'_, 探索> {
    // 原子1つを、いまの束縛の全部へ当てる。
    fn 原子を当てる(&self, 原子: 本体の原子, 束縛一覧: &[束縛]) -> 原子の答え {
        let mut 答え = 原子の答え::default();
        for 束縛 in 束縛一覧 {
            答え.併せる(match 原子 {
                本体の原子::宣言の原子(宣言の原子) => self.宣言の原子を当てる(宣言の原子, 束縛),
                本体の原子::表記が型を名指す { 型 } => self.名指す型を当てる(束縛, 型),
                本体の原子::マーカーが付いている { 変数, マーカー名 } => self.マーカーが付いている束縛だけを残す(束縛, 変数, マーカー名),
            });
        }
        答え
    }

    // 宣言の原子を1つの束縛へ当て、宣言の候補ごとに分かれた束縛と、表記を当てられなかった欠けを返す。
    fn 宣言の原子を当てる(&self, 原子: 宣言の原子, 束縛: &束縛) -> 原子の答え {
        let プリミティブな宣言 = self.プリミティブな宣言;
        let 束縛一覧 = match 原子 {
            宣言の原子::フィールドの型の表記を持つ { 持ち主 } => プリミティブな宣言
                .フィールドの型の表記一覧()
                .iter()
                .filter_map(|件| 束縛.宣言から当てる(持ち主, 件.持ち主().clone(), 件.表記().clone(), 件.出どころ()))
                .collect(),
            宣言の原子::エンティティの識別子の関連型を持つ { エンティティ } => プリミティブな宣言
                .エンティティの識別子の関連型一覧()
                .iter()
                .filter_map(|件| 束縛.宣言から当てる(エンティティ, 件.エンティティ().clone(), 件.表記().clone(), 件.出どころ()))
                .collect(),
            宣言の原子::役割の型引数を持つ { 役割, 位置, 処理 } => return self.役割の型引数を当てる(役割, 位置, 処理, 束縛),
        };
        原子の答え::束縛一覧から生成する(束縛一覧)
    }

    // 変数に当たった概念に付いているマーカーがその名前のマーカーを含むなら束縛をそのまま残し、含まなければ落とす。付いているマーカーを問うだけであり、表記を読まないため欠けを出さない。
    // 変数に何も当たっていなければ、規則が付いているマーカーを問う変数を先の原子に当てさせるという不変条件が破れている。
    fn マーカーが付いている束縛だけを残す(&self, 束縛: &束縛, 変数: 概念の変数, マーカー名: &str) -> 原子の答え {
        let Some(概念) = 束縛.当たっている概念(変数) else {
            panic!("`マーカーが付いている` が何も当たっていない変数 {変数:?} の付いているマーカーを問うた: 定義の式の規則は付いているマーカーを問う変数を先の原子に当てさせるという不変条件が破れた");
        };
        let 含むか = self.各型に付いているマーカーの一覧.概念に付いているマーカー(概念).iter().any(|トレイト| トレイト.識別子().名前() == マーカー名);
        原子の答え::束縛一覧から生成する(if 含むか { vec![束縛.clone()] } else { Vec::new() })
    }
}
