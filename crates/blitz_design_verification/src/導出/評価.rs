//! 定義の式をプリミティブな事実の上で評価する工程。受け取るのは事実と型の名前の解決の口、返すのは導出の結果である。
//!
//! 規則ごとに、空の束縛1つから始めて本体の原子を左から当て、残った束縛ごとに頭の関係を1件導く。規則の順と事実の順を保つため、
//! 導いた関係の並びは入力の並びから一意に決まる。同じ表記を2つの規則が読めば、読めなかった欠けも2件になる。
//! 欠けを重ねて数えるのは、段階2の前の抽出器が型引数の位置ごとに表記を読み、同じ数の欠けを出していたためである。
//! 型の表記を読む原子(`表記が型を名指す`)の評価は `名指す型の読み取り` が、頭の関係を結果へ足す操作は `結果` が持つ。

use super::名前の解決::型の名前の解決;
use super::束縛::束縛;
use super::結果::{導出の欠け, 導出の結果};
use super::規則::定義の式;
use super::規則の本体の原子::{事実の原子, 本体の原子};
use super::関係を導く事実::{プリミティブな事実, 型の表記};

/// 原子1つを当てた答え。成り立った束縛の一覧と、表記を読めずに落とした箇所の一覧である。
#[derive(Default)]
pub(super) struct 原子の答え {
    pub(super) 束縛一覧: Vec<束縛>,
    pub(super) 欠け一覧: Vec<導出の欠け>,
}

/// 事実と解決の口を借りて規則の本体の原子を当てる工程。
pub(super) struct 評価の工程<'a, 解決: 型の名前の解決> {
    pub(super) 事実: &'a プリミティブな事実,
    pub(super) 解決: &'a 解決,
}

impl 定義の式 {
    /// 全ての規則をその事実の上で評価する。型の表記を書いた場所から型の定義をたどるときは、渡された解決の口へ問う。
    pub fn 評価する(&self, 事実: &プリミティブな事実, 解決: &impl 型の名前の解決) -> 導出の結果 {
        let 工程 = 評価の工程 { 事実, 解決 };
        let mut 結果 = 導出の結果::default();
        for 規則 in self.規則一覧() {
            let mut 束縛一覧 = vec![束縛::空()];
            for 原子 in &規則.本体 {
                let 答え = 工程.原子を当てる(*原子, &束縛一覧);
                結果.欠け一覧.extend(答え.欠け一覧);
                束縛一覧 = 答え.束縛一覧;
            }
            for 束縛 in &束縛一覧 {
                結果.規則の頭を足す(規則, 束縛);
            }
        }
        結果
    }
}

impl 原子の答え {
    // 別の束縛から得た答えを後ろへ併せる。
    fn 併せる(&mut self, 他: Self) {
        self.束縛一覧.extend(他.束縛一覧);
        self.欠け一覧.extend(他.欠け一覧);
    }
}

impl<解決: 型の名前の解決> 評価の工程<'_, 解決> {
    // 原子1つを、いまの束縛の全部へ当てる。
    fn 原子を当てる(&self, 原子: 本体の原子, 束縛一覧: &[束縛]) -> 原子の答え {
        let mut 答え = 原子の答え::default();
        for 束縛 in 束縛一覧 {
            答え.併せる(match 原子 {
                本体の原子::事実(事実の原子) => 原子の答え {
                    束縛一覧: self.事実の原子を当てる(事実の原子, 束縛),
                    欠け一覧: Vec::new(),
                },
                本体の原子::表記が型を名指す { 型 } => self.名指す型を当てる(束縛, 型),
            });
        }
        答え
    }

    // 事実の原子を1つの束縛へ当て、事実の候補ごとに分かれた束縛を返す。
    fn 事実の原子を当てる(&self, 原子: 事実の原子, 束縛: &束縛) -> Vec<束縛> {
        let 事実 = self.事実;
        let その役割の宣言一覧 = |役割| 事実.関数の役割の宣言一覧.iter().filter(move |件| 件.役割 == 役割);
        match 原子 {
            事実の原子::フィールドの型の表記を持つ { 持ち主 } => 事実.フィールドの型の表記一覧.iter().filter_map(|件| 束縛.事実から当てる(持ち主, 件.持ち主.clone(), 件.表記.clone(), &件.出どころ)).collect(),
            事実の原子::エンティティの識別子の関連型を持つ { エンティティ } => 事実
                .エンティティの識別子の関連型一覧
                .iter()
                .filter_map(|件| 束縛.事実から当てる(エンティティ, 件.エンティティ.clone(), 件.表記.clone(), &件.出どころ))
                .collect(),
            事実の原子::役割の型引数を持つ { 役割, 位置, 処理 } => その役割の宣言一覧(役割)
                .filter_map(|件| 束縛.事実から当てる(処理, 件.処理.参照を組む(), 件.型引数の表記一覧.get(位置)?.clone(), &件.出どころ))
                .collect(),
            事実の原子::役割の定義が固定で受け取る { 役割, 型名, 処理 } => その役割の宣言一覧(役割)
                .filter_map(|件| 束縛.事実から当てる(処理, 件.処理.参照を組む(), 型の表記::型引数の無い場所で生成する(型名), &件.出どころ))
                .collect(),
        }
    }
}
