//! 定義の式をプリミティブな事実の上で評価する工程。受け取るのは事実と型の名前の解決の口、返すのは導出の結果である。
//!
//! 規則ごとに、空の束縛1つから始めて本体の原子を左から当て、残った束縛ごとに頭の関係を1件導く。規則の順と事実の順を保つため、
//! 導いた関係の並びは入力の並びから一意に決まる。同じ表記を2つの規則が読めば、読めなかった欠けも2件になる。
//! 欠けを重ねて数えるのは、段階2の前の抽出器が型引数の位置ごとに表記を読み、同じ数の欠けを出していたためである。
//! 型の表記を読む原子(`表記が型を名指す`)の評価は `名指す型の読み取り` が、頭の関係を導出の結果へ足す操作は `導出の結果の定義` が持つ。

use super::プリミティブな事実の定義::{プリミティブな事実, 型の表記};
use super::型の名前の解決の定義::型の名前の解決;
use super::定義の式の規則一覧::定義の式;
use super::導出の結果の定義::{導出の欠け, 導出の欠けの理由, 導出の結果};
use super::束縛::束縛;
use super::規則の本体の原子::{事実の原子, 本体の原子, 概念の変数};
use super::関数の役割の定義::関数の役割;

/// 原子1つを当てた答え。成り立った束縛の一覧と、表記を読めずに落とした箇所の一覧である。
#[derive(Default)]
pub(super) struct 原子の答え {
    pub(super) 束縛一覧: Vec<束縛>,
    pub(super) 欠け一覧: Vec<導出の欠け>,
}

/// 事実と解決の口を借りて規則の本体の原子を当てる工程。
pub(super) struct 評価の工程<'a, 解決: 型の名前の解決> {
    pub(super) 事実: &'a プリミティブな事実,
    pub(super) 解決: &'a 解決,
}

impl 定義の式 {
    /// 全ての規則をその事実の上で評価する。型の表記を書いた場所から型の定義をたどるときは、渡された解決の口へ問う。
    pub fn 評価する(&self, 事実: &プリミティブな事実, 解決: &impl 型の名前の解決) -> 導出の結果 {
        let 工程 = 評価の工程 { 事実, 解決 };
        let mut 結果 = 導出の結果::default();
        for 規則 in self.規則一覧() {
            let mut 束縛一覧 = vec![束縛::空()];
            for 原子 in &規則.本体 {
                let 答え = 工程.原子を当てる(*原子, &束縛一覧);
                結果.欠け一覧.extend(答え.欠け一覧);
                束縛一覧 = 答え.束縛一覧;
            }
            for 束縛 in &束縛一覧 {
                結果.規則の頭を足す(規則, 束縛);
            }
        }
        結果
    }
}

impl 原子の答え {
    // 別の束縛から得た答えを後ろへ併せる。
    fn 併せる(&mut self, 他: Self) {
        self.束縛一覧.extend(他.束縛一覧);
        self.欠け一覧.extend(他.欠け一覧);
    }
}

impl<解決: 型の名前の解決> 評価の工程<'_, 解決> {
    // 原子1つを、いまの束縛の全部へ当てる。
    fn 原子を当てる(&self, 原子: 本体の原子, 束縛一覧: &[束縛]) -> 原子の答え {
        let mut 答え = 原子の答え::default();
        for 束縛 in 束縛一覧 {
            答え.併せる(match 原子 {
                本体の原子::事実(事実の原子) => self.事実の原子を当てる(事実の原子, 束縛),
                本体の原子::表記が型を名指す { 型 } => self.名指す型を当てる(束縛, 型),
            });
        }
        答え
    }

    // 事実の原子を1つの束縛へ当て、事実の候補ごとに分かれた束縛と、表記を当てられなかった欠けを返す。
    fn 事実の原子を当てる(&self, 原子: 事実の原子, 束縛: &束縛) -> 原子の答え {
        let 事実 = self.事実;
        let 束縛一覧 = match 原子 {
            事実の原子::フィールドの型の表記を持つ { 持ち主 } => 事実.フィールドの型の表記一覧.iter().filter_map(|件| 束縛.事実から当てる(持ち主, 件.持ち主.clone(), 件.表記.clone(), &件.出どころ)).collect(),
            事実の原子::エンティティの識別子の関連型を持つ { エンティティ } => 事実
                .エンティティの識別子の関連型一覧
                .iter()
                .filter_map(|件| 束縛.事実から当てる(エンティティ, 件.エンティティ.clone(), 件.表記.clone(), &件.出どころ))
                .collect(),
            事実の原子::役割の型引数を持つ { 役割, 位置, 処理 } => return self.役割の型引数を当てる(役割, 位置, 処理, 束縛),
            事実の原子::役割の定義が固定で受け取る { 役割, 型名, 処理 } => 事実
                .関数の役割の宣言一覧
                .iter()
                .filter(|件| 件.役割 == 役割)
                .filter_map(|件| 束縛.事実から当てる(処理, 件.処理.参照を組む(), 型の表記::型引数の無い場所で生成する(型名), &件.出どころ))
                .collect(),
        };
        原子の答え { 束縛一覧, 欠け一覧: Vec::new() }
    }

    // その役割の宣言ごとに、その位置の型引数の表記を当てる。事実の型は公開のフィールドを持ち、型引数の数が役割の取る数と等しいことを
    // 型では守らないため、評価器がここで確かめる。数が合わない宣言はどの位置の表記が何を指すかを決められないため、束縛を作らず欠けとして返す。
    fn 役割の型引数を当てる(&self, 役割: 関数の役割, 位置: usize, 処理: 概念の変数, 束縛: &束縛) -> 原子の答え {
        let mut 答え = 原子の答え::default();
        for 件 in self.事実.関数の役割の宣言一覧.iter().filter(|件| 件.役割 == 役割) {
            let 読めた数 = 件.型引数の表記一覧.len();
            match 件.型引数の表記一覧.get(位置) {
                Some(表記) if 読めた数 == 役割.型引数の数() => 答え.束縛一覧.extend(束縛.事実から当てる(処理, 件.処理.参照を組む(), 表記.clone(), &件.出どころ)),
                _ => 答え.欠け一覧.push(導出の欠け {
                    出どころ: 件.出どころ.clone(),
                    理由: 導出の欠けの理由::役割の型引数の数が合わない { 役割, 位置, 読めた数 },
                }),
            }
        }
        答え
    }
}
