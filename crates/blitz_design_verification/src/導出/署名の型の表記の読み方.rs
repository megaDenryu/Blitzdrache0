//! 署名の型の表記の読み方とは、関数の署名の引数と戻り値の型の表記から、その表記が名指す型とトレイトを採る定義の式の側の知識のことである。
//! 依存を持たない純粋な関数だけを置く。受け取るのは型の表記の書かれた文字列と読み通す範囲、返すのはその表記が名指す型かトレイトか読めない理由の並びである。
//!
//! フィールドの型の表記の読み方(`型の表記の読み方`)を部品として呼び、フィールドの読み方そのものは変えない。変えると保持するの定義が変わるためである。
//! 署名の側だけで読むのは次のとおりである。1つの表記が複数の型を名指しうるため、答えは並びである。
//! - 参照と寿命を落とす(フィールドの読み方と同じ部品を使う)。
//! - `Result<T, E>` と組 `(A, B)` と `blitz_design` の意味型(`遷移成功結果<状態, 出来事>` など)から、それぞれの型を読む。単位型 `()` は何も名指さない。
//! - 剥がす包み(`Vec`・`Option` 等)とスライス・配列 `[T]`・`[T; N]` の中身を、署名の読み方で読み直す。`Option<Result<T, E>>` も読めるようにするためである。
//! - `impl トレイト` と `dyn トレイト` から、`+` で並べた境界のそれぞれのトレイトを読み、そのトレイトの型の引数と関連型の指定(`Iterator<Item = T>` の `T`)も読む。
//!   寿命と `?Sized` の境界は何も名指さない。
//! - 関数ポインタ `fn(A) -> B` とクロージャのトレイト `Fn(A) -> B`(`FnMut`・`FnOnce`)から、引数と戻り値の型を読む(`関数の型の読み方`)。
//! - 寿命だけの型引数(`Formatter<'_>`)を落とし、型の引数を持たない標準ライブラリの型(`std::fmt::Result`)を設計概念にしない(`読み通す型と標準の型の見分け`)。
//! - パスの修飾が付いた名前(`fmt::Result`・`crate::a::型`・`blitz_math::変位<blitz_math::ワールド>`)は、修飾と名前に分けて答える(`名前の読み方`)。
//!   修飾がどのモジュールを指すかは `use` を読む解決の口が決めるため、定義の式の評価器が口へ問う。
//!
//! **読み通す範囲は2つある。** `引数に取る` と `返す` は、包みとトレイトと関数の型の中まで読む(`包みとトレイトの中まで`)。
//! `そのまま返す` は、戻り値そのものと `Result`・組・意味型の成分と、値を1つだけ必ず持つ包み(`Box`・`Arc`)の中身だけを読み(`値そのものと成分だけ`)、
//! 0個か複数の値を持つ包み(`Vec`・`Option` 等)とスライスと `impl`・`dyn` のトレイトと関数の型の中を読まない。
//! 候補を並べて返す関数(`Vec<状態>`)や次の値を順に渡す関数(`impl Iterator<Item = 状態>`)は、状態の値そのものを返していないためである。
//! 読まない位置の型は `返す` の読み方が同じ表記から読むため、関係は失われない。

#[path = "署名の型の表記の読み方/名前の読み方.rs"]
