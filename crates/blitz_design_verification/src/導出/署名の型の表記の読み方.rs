//! 署名の型の表記の読み方とは、関数の署名の引数と戻り値の型の表記から、その表記が名指す型とトレイトを採る定義の式の側の知識のことである。
//! 依存を持たない純粋な関数だけを置く。受け取るのは型の表記の書かれた文字列、返すのはその表記が名指す型かトレイトか読めない理由の並びである。
//!
//! フィールドの型の表記の読み方(`型の表記の読み方`)を部品として呼び、フィールドの読み方そのものは変えない。変えると保持するの定義が変わるためである。
//! 署名の側だけで読むのは次のとおりである。1つの表記が複数の型を名指しうるため、答えは並びである。
//! - 参照と寿命を落とす(フィールドの読み方と同じ部品を使う)。
//! - `Result<T, E>` と組 `(A, B)` から、それぞれの型を読む。単位型 `()` は何も名指さない。
//! - 剥がす包み(`Vec`・`Option` 等)とスライス・配列 `[T]`・`[T; N]` の中身を、署名の読み方で読み直す。`Option<Result<T, E>>` も読めるようにするためである。
//! - `impl トレイト` と `dyn トレイト` から、`+` で並べた境界のそれぞれのトレイトを読む。寿命と `?Sized` の境界は何も名指さない。
//!
//! 残る表記はフィールドの読み方で読む。関数ポインタ・クロージャのトレイト(`Fn(u8) -> u8`)・パスの修飾が付いた関連型(`Self::関連型`・`口::関連型`)は、
//! その読み方が読めない表記と答える。型引数の名前は、この読み方では型として答え、定義の式が書いた場所の型引数と照らして読めない表記に数える。

use super::型の表記の読み方::{剥がす包みか, 参照を落とす, 型の表記の読み取り, 型の表記を読む};
use super::型の表記を読めない理由の定義::型の表記を読めない理由;
use super::表記が名指す型の定義::表記が名指す型;

/// `Result` の包みとして受け取る書かれた文字列。
const 結果の包みの表記一覧: [&str; 3] = ["Result", "std::result::Result", "core::result::Result"];

/// 署名の型の表記1つが名指すもの1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 署名の型の表記の読み取り {
    /// 型を名指した。
    型(表記が名指す型),
    /// `impl` か `dyn` の境界のトレイトを名指した。
    トレイト(表記が名指す型),
    /// 読めない表記である。
    読めない(型の表記を読めない理由),
}

/// 署名の型の表記から、名指す型とトレイトを並べる。プリミティブと単位型と値を持たない型は並べない。
pub fn 署名の型の表記を読む(表記: &str) -> Vec<署名の型の表記の読み取り> {
    let 芯 = 参照を落とす(表記).trim();
    if 芯.is_empty() || 芯 == "()" {
        return Vec::new();
    }
    if let Some(中) = 芯.strip_prefix('(').and_then(|残り| 残り.strip_suffix(')')) {
        return 最上位で分ける(中, ',').into_iter().flat_map(署名の型の表記を読む).collect();
    }
    if let Some(中) = 芯.strip_prefix('[').and_then(|残り| 残り.strip_suffix(']')) {
        return 最上位で分ける(中, ';').first().map_or_else(Vec::new, |要素| 署名の型の表記を読む(要素));
    }
    if let Some(境界) = 芯.strip_prefix("impl ").or_else(|| 芯.strip_prefix("dyn ")) {
        return 最上位で分ける(境界, '+').into_iter().filter_map(境界のトレイトを読む).collect();
    }
    if let Some((前, 型引数)) = 芯.split_once('<').and_then(|(前, 残り)| Some((前, 残り.rsplit_once('>')?.0))) {
        if 結果の包みの表記一覧.contains(&前.trim()) {
            return 最上位で分ける(型引数, ',').into_iter().flat_map(署名の型の表記を読む).collect();
        }
        if 剥がす包みか(前) {
            return 署名の型の表記を読む(型引数);
        }
    }
    match 型の表記を読む(芯) {
        型の表記の読み取り::設計概念である(型) => vec![署名の型の表記の読み取り::型(型)],
        型の表記の読み取り::プリミティブである | 型の表記の読み取り::値を持たない型である => Vec::new(),
        型の表記の読み取り::保証範囲の外(理由) => vec![署名の型の表記の読み取り::読めない(理由)],
    }
}

// `impl`・`dyn` の境界1つから、そのトレイトを読む。寿命(`'a`)と `?Sized` は何も名指さない。
fn 境界のトレイトを読む(境界: &str) -> Option<署名の型の表記の読み取り> {
    let 境界 = 境界.trim();
    if 境界.is_empty() || 境界.starts_with('\'') || 境界.starts_with('?') {
        return None;
    }
    match 型の表記を読む(境界) {
        型の表記の読み取り::設計概念である(トレイト) => Some(署名の型の表記の読み取り::トレイト(トレイト)),
        型の表記の読み取り::プリミティブである | 型の表記の読み取り::値を持たない型である => None,
        型の表記の読み取り::保証範囲の外(理由) => Some(署名の型の表記の読み取り::読めない(理由)),
    }
}

// 表記を、どの括弧の中でもない位置の区切りの文字で分け、空でない部分を並べる。`->` の `>` は山括弧を閉じない。
fn 最上位で分ける(表記: &str, 区切り: char) -> Vec<&str> {
    let (mut 一覧, mut 始まり, mut 深さ, mut 直前) = (Vec::new(), 0, 0usize, ' ');
    for (位置, 文字) in 表記.char_indices() {
        match 文字 {
            '<' | '(' | '[' => 深さ += 1,
            '>' if 直前 == '-' => {}
            '>' | ')' | ']' => 深さ = 深さ.saturating_sub(1),
            _ if 文字 == 区切り && 深さ == 0 => {
                一覧.push(&表記[始まり..位置]);
                始まり = 位置 + 文字.len_utf8();
            }
            _ => {}
        }
        直前 = 文字;
    }
    一覧.push(&表記[始まり..]);
    一覧.into_iter().map(str::trim).filter(|部分| !部分.is_empty()).collect()
}
