/// 署名の型の表記1つが名指すもの1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 署名の型の表記の読み取り {
    /// 型を名指した。
    型(表記が名指す型),
    /// `impl` か `dyn` の境界のトレイトを名指した。
    トレイト(表記が名指す型),
    /// パスの修飾が付いた型かトレイトを名指した。修飾がどのモジュールを指すかは、評価器が解決の口へ問う。
    修飾された名前 {
        /// 名前の前の修飾(`fmt`・`crate::a`)。
        修飾: String,
        /// 修飾を落とした名前が名指す型かトレイト。
        名前: 表記が名指す型,
        /// 型かトレイトか。
        種類: Rustの項目の種類,
    },
    /// 読めない表記である。
    読めない(型の表記を読めない理由),
}

/// 署名の型の表記をどこまで読み通すか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 署名の読み通す範囲 {
    /// 包み・スライス・配列・`impl`・`dyn` のトレイト・関数の型の中まで読む。`引数に取る` と `返す` が使う。
    包みとトレイトの中まで,
    /// 値そのものと、`Result`・組・意味型の成分と、値を1つだけ必ず持つ包みの中身だけを読む。`そのまま返す` が使う。
    値そのものと成分だけ,
}

/// 署名の型の表記から、名指す型とトレイトを並べる。プリミティブと単位型と値を持たない型は並べない。
pub fn 署名の型の表記を読む(表記: &str, 範囲: 署名の読み通す範囲) -> Vec<署名の型の表記の読み取り> {
    let 芯 = 参照を落とす(表記).trim();
    let 中まで読むか = 範囲 == 署名の読み通す範囲::包みとトレイトの中まで;
    let 並べて読む = |並び: &str, 区切り: char| 最上位で分ける(並び, 区切り).into_iter().flat_map(|部分| 署名の型の表記を読む(部分, 範囲)).collect();
    if 芯.is_empty() || 芯 == "()" {
        return Vec::new();
    }
    if let Some(中) = 芯.strip_prefix('(').and_then(|残り| 残り.strip_suffix(')')) {
        return 並べて読む(中, ',');
    }
    if let Some(中) = 芯.strip_prefix('[').and_then(|残り| 残り.strip_suffix(']')) {
        return if 中まで読むか {
            最上位で分ける(中, ';').first().map_or_else(Vec::new, |要素| 署名の型の表記を読む(要素, 範囲))
        } else {
            Vec::new()
        };
    }
    if let Some(境界) = 芯.strip_prefix("impl ").or_else(|| 芯.strip_prefix("dyn ")) {
        return if 中まで読むか {
            最上位で分ける(境界, '+').into_iter().flat_map(境界のトレイトを読む).collect()
        } else {
            Vec::new()
        };
    }
    if let Some((引数の並び, 戻り値)) = 関数ポインタの引数と戻り値(芯) {
        return if 中まで読むか { 関数の型の中を読む(引数の並び, 戻り値) } else { Vec::new() };
    }
    if let Some((前, 型引数)) = 型引数を分ける(芯) {
        if 中身を読み通す型か(前) {
            return 並べて読む(型引数, ',');
        }
        if 剥がす包みか(前) {
            return if 中まで読むか || 値を1つだけ持つ包みか(前) {
                署名の型の表記を読む(型引数, 範囲)
            } else {
                Vec::new()
            };
        }
        if 寿命だけの型引数か(型引数) {
            return 署名の型の表記を読む(前, 範囲);
        }
    }
    if 標準ライブラリの型か(芯) {
        return Vec::new();
    }
    名前を読む(芯, Rustの項目の種類::型)
}

// 型引数を持つ表記を、型引数の前と、最も外側の山括弧の内側に分ける。型引数を持たないなら無しである。
fn 型引数を分ける(表記: &str) -> Option<(&str, &str)> {
    表記.split_once('<').and_then(|(前, 残り)| Some((前, 残り.rsplit_once('>')?.0)))
}

// 表記を、どの括弧の中でもない位置の区切りの文字で分け、空でない部分を並べる。`->` の `>` は山括弧を閉じない。
fn 最上位で分ける(表記: &str, 区切り: char) -> Vec<&str> {
    let (mut 一覧, mut 始まり, mut 深さ, mut 直前) = (Vec::new(), 0, 0usize, ' ');
    for (位置, 文字) in 表記.char_indices() {
        match 文字 {
            '<' | '(' | '[' => 深さ += 1,
            '>' if 直前 == '-' => {}
            '>' | ')' | ']' => 深さ = 深さ.saturating_sub(1),
            _ if 文字 == 区切り && 深さ == 0 => {
                一覧.push(&表記[始まり..位置]);
                始まり = 位置 + 文字.len_utf8();
            }
            _ => {}
        }
        直前 = 文字;
    }
    一覧.push(&表記[始まり..]);
    一覧.into_iter().map(str::trim).filter(|部分| !部分.is_empty()).collect()
}
