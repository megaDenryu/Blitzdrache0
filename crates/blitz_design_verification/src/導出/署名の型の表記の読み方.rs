use super::型の表記の読み方::{剥がす包みか, 参照を落とす, 型の表記の読み取り, 型の表記を読む};
use super::型の表記を読めない理由の定義::型の表記を読めない理由;
use super::表記が名指す型の定義::表記が名指す型;
use 読み通す型と標準の型の見分け::{中身を読み通す型か, 寿命だけの型引数か, 標準ライブラリの型か};

/// 署名の型の表記1つが名指すもの1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 署名の型の表記の読み取り {
    /// 型を名指した。
    型(表記が名指す型),
    /// `impl` か `dyn` の境界のトレイトを名指した。
    トレイト(表記が名指す型),
    /// 読めない表記である。
    読めない(型の表記を読めない理由),
}

/// 署名の型の表記から、名指す型とトレイトを並べる。プリミティブと単位型と値を持たない型は並べない。
pub fn 署名の型の表記を読む(表記: &str) -> Vec<署名の型の表記の読み取り> {
    let 芯 = 参照を落とす(表記).trim();
    if 芯.is_empty() || 芯 == "()" {
        return Vec::new();
    }
    if let Some(中) = 芯.strip_prefix('(').and_then(|残り| 残り.strip_suffix(')')) {
        return 最上位で分ける(中, ',').into_iter().flat_map(署名の型の表記を読む).collect();
    }
    if let Some(中) = 芯.strip_prefix('[').and_then(|残り| 残り.strip_suffix(']')) {
        return 最上位で分ける(中, ';').first().map_or_else(Vec::new, |要素| 署名の型の表記を読む(要素));
    }
    if let Some(境界) = 芯.strip_prefix("impl ").or_else(|| 芯.strip_prefix("dyn ")) {
        return 最上位で分ける(境界, '+').into_iter().flat_map(境界のトレイトを読む).collect();
    }
    if let Some((前, 型引数)) = 型引数を分ける(芯) {
        if 中身を読み通す型か(前) {
            return 最上位で分ける(型引数, ',').into_iter().flat_map(署名の型の表記を読む).collect();
        }
        if 剥がす包みか(前) {
            return 署名の型の表記を読む(型引数);
        }
        if 寿命だけの型引数か(型引数) {
            return 署名の型の表記を読む(前);
        }
    }
    if 標準ライブラリの型か(芯) {
        return Vec::new();
    }
    match 型の表記を読む(芯) {
        型の表記の読み取り::設計概念である(型) => vec![署名の型の表記の読み取り::型(型)],
        型の表記の読み取り::プリミティブである | 型の表記の読み取り::値を持たない型である => Vec::new(),
        型の表記の読み取り::保証範囲の外(理由) => vec![署名の型の表記の読み取り::読めない(理由)],
    }
}

// `impl`・`dyn` の境界1つから、そのトレイトと、トレイトの型の引数と関連型の指定が名指す型を読む。寿命(`'a`)と `?Sized` は何も名指さない。
// 標準ライブラリのトレイトは設計概念にせず、型の引数だけを読む。
fn 境界のトレイトを読む(境界: &str) -> Vec<署名の型の表記の読み取り> {
    let 境界 = 境界.trim();
    if 境界.is_empty() || 境界.starts_with('\'') || 境界.starts_with('?') {
        return Vec::new();
    }
    let (トレイト, 引数の読み取り一覧): (&str, Vec<署名の型の表記の読み取り>) = match 型引数を分ける(境界) {
        Some((前, 型引数)) if !前.contains('(') => (前.trim(), 最上位で分ける(型引数, ',').into_iter().flat_map(|引数| 署名の型の表記を読む(関連型の指定なら型の側(引数))).collect()),
        _ => (境界, Vec::new()),
    };
    if 標準ライブラリの型か(トレイト) {
        return 引数の読み取り一覧;
    }
    let トレイトの読み取り = match 型の表記を読む(トレイト) {
        型の表記の読み取り::設計概念である(トレイト) => Some(署名の型の表記の読み取り::トレイト(トレイト)),
        型の表記の読み取り::プリミティブである | 型の表記の読み取り::値を持たない型である => None,
        型の表記の読み取り::保証範囲の外(理由) => Some(署名の型の表記の読み取り::読めない(理由)),
    };
    トレイトの読み取り.into_iter().chain(引数の読み取り一覧).collect()
}

// 型引数を持つ表記を、型引数の前と、最も外側の山括弧の内側に分ける。型引数を持たないなら無しである。
fn 型引数を分ける(表記: &str) -> Option<(&str, &str)> {
    表記.split_once('<').and_then(|(前, 残り)| Some((前, 残り.rsplit_once('>')?.0)))
}

// トレイトの型の引数1つが関連型の指定(`Item = T`)なら、指定した型の側 `T`。そうでなければ引数のままである。
fn 関連型の指定なら型の側(引数: &str) -> &str {
    match 最上位で分ける(引数, '=').as_slice() {
        [名前, 型] if !名前.contains(['<', '(']) => 型,
        _ => 引数,
    }
}

// 表記を、どの括弧の中でもない位置の区切りの文字で分け、空でない部分を並べる。`->` の `>` は山括弧を閉じない。
fn 最上位で分ける(表記: &str, 区切り: char) -> Vec<&str> {
    let (mut 一覧, mut 始まり, mut 深さ, mut 直前) = (Vec::new(), 0, 0usize, ' ');
    for (位置, 文字) in 表記.char_indices() {
        match 文字 {
            '<' | '(' | '[' => 深さ += 1,
            '>' if 直前 == '-' => {}
            '>' | ')' | ']' => 深さ = 深さ.saturating_sub(1),
            _ if 文字 == 区切り && 深さ == 0 => {
                一覧.push(&表記[始まり..位置]);
                始まり = 位置 + 文字.len_utf8();
            }
            _ => {}
        }
        直前 = 文字;
    }
    一覧.push(&表記[始まり..]);
    一覧.into_iter().map(str::trim).filter(|部分| !部分.is_empty()).collect()
}
