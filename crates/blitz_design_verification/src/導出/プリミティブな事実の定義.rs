//! プリミティブな事実とは、抽出器がRustのソースから読む、コンパイラが知っている形の事実のことである(Issue #193 の契約)。
//! 型の定義・フィールドの型の表記・関数の役割の宣言・エンティティの識別子の関連型・関数の署名(`関数の署名の事実の定義`)の5種を持つ。マーカーの実装と上位トレイトの宣言は
//! 同じ高さの事実であり、`分類の事実` が持つ。
//!
//! **事実は設計の意味を持たない。** フィールドの型の表記は包みを剥がす前の書かれた文字列のまま運び、何を保持するかは定義の式が決める。
//! 関数の役割の宣言は型引数の書かれた文字列を並びのまま運び、どの位置が何を変換用の素材にするかは定義の式が決める。
//! 後で #175 が事実を足すとき、型の表記を持つ事実(「引数に取る」等)は、この型へ一覧を1つ足し、事実の原子と定義の式の規則を足せば足せる。
//! 両端が節点の事実(「呼ぶ」「コンポジションルートが組む」等)と、分類と組み合わせる定義は、束縛・結果・評価器の拡張が要る(`規則の本体の原子` の冒頭を見る)。

use crate::{事実の出どころ, 設計概念, 設計概念への参照};

use super::型引数の境界の定義::{型引数の境界, 型引数を境界へ読み替える};
use super::関数の役割の定義::関数の役割;
use super::関数の署名の事実の定義::関数の署名の事実;

/// ソースに書かれた型の表記1件。包みを剥がす前の書かれた文字列と、その表記を書いた場所で有効な型引数の名前の一覧と、関数の署名なら型引数の境界の一覧を持つ。
/// 型引数の名前を持つのは、`struct 包み<状態> { 中身: 状態 }` の `状態` が設計概念でなく型引数であることを、定義の式が表記だけから見分けるためである。
/// 境界を持つのは、署名の読み方が境界を持つ型引数を境界のトレイトとして読むためである(`型引数の境界`)。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 型の表記 {
    書かれた文字列: String,
    有効な型引数名一覧: Vec<String>,
    型引数の境界一覧: Vec<型引数の境界>,
}

/// `struct`・`enum` の宣言1件。その型の節点を立てる。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 型の定義の事実 {
    /// 宣言した型の節点。
    pub 型: 設計概念,
    /// この1件がどのソースのどの行から出たか。
    pub 出どころ: 事実の出どころ,
}

/// `struct`・`enum` のフィールド1つの型の表記。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct フィールドの型の表記の事実 {
    /// フィールドを持つ型への参照。
    pub 持ち主: 設計概念への参照,
    /// フィールドの型の表記。
    pub 表記: 型の表記,
    /// この1件がどのソースのどの行から出たか。
    pub 出どころ: 事実の出どころ,
}

/// `impl Mエンティティ for 型 { type 識別子 = 表記; }` の1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct エンティティの識別子の関連型の事実 {
    /// `Mエンティティ` を実装した型への参照。
    pub エンティティ: 設計概念への参照,
    /// 関連型 `識別子` の右辺の表記。
    pub 表記: 型の表記,
    /// この1件がどのソースのどの行から出たか。関連型の行を指す。
    pub 出どころ: 事実の出どころ,
}

/// `const _: M遷移関数<..> = M遷移関数::生成する(所有者::関数);` の形の関数の役割の宣言1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 関数の役割の宣言の事実 {
    /// 役割に包まれた関数の節点。種類は処理である。
    pub 処理: 設計概念,
    /// 宣言した役割。
    pub 役割: 関数の役割,
    /// 役割の型引数の表記を位置の順に並べた一覧。
    pub 型引数の表記一覧: Vec<型の表記>,
    /// この1件がどのソースのどの行から出たか。
    pub 出どころ: 事実の出どころ,
}

/// 抽出器が出すプリミティブな事実の全体。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct プリミティブな事実 {
    /// 型の定義の事実の一覧。
    pub 型の定義一覧: Vec<型の定義の事実>,
    /// フィールドの型の表記の事実の一覧。
    pub フィールドの型の表記一覧: Vec<フィールドの型の表記の事実>,
    /// エンティティの識別子の関連型の事実の一覧。
    pub エンティティの識別子の関連型一覧: Vec<エンティティの識別子の関連型の事実>,
    /// 関数の役割の宣言の事実の一覧。
    pub 関数の役割の宣言一覧: Vec<関数の役割の宣言の事実>,
    /// 関数の署名の事実の一覧。
    pub 関数の署名一覧: Vec<関数の署名の事実>,
}

impl 型の表記 {
    /// 書かれた文字列と、その表記を書いた場所で有効な型引数の名前の一覧から組む。
    pub fn 生成する(書かれた文字列: &str, 有効な型引数名一覧: Vec<String>) -> Self {
        Self {
            書かれた文字列: 書かれた文字列.to_string(),
            有効な型引数名一覧,
            型引数の境界一覧: Vec::new(),
        }
    }

    /// その表記を書いた場所の型引数の境界を添えた表記。関数の署名の表記だけが境界を持つ。
    pub fn 境界を添える(self, 型引数の境界一覧: Vec<型引数の境界>) -> Self {
        Self { 型引数の境界一覧, ..self }
    }

    /// 境界を持つ型引数とその関連型を、境界のトレイトの `impl` の表記へ読み替えた書かれた文字列。署名の読み方がこれを読む。
    pub(super) fn 型引数を境界へ読み替えた書かれた文字列(&self) -> String {
        型引数を境界へ読み替える(&self.書かれた文字列, &self.型引数の境界一覧)
    }

    /// 型引数を導入しない場所(関数の役割の型引数・関連型の右辺)に書いた表記を組む。
    pub fn 型引数の無い場所で生成する(書かれた文字列: &str) -> Self {
        Self::生成する(書かれた文字列, Vec::new())
    }

    /// 包みを剥がす前の書かれた文字列。
    pub fn 書かれた文字列(&self) -> &str {
        &self.書かれた文字列
    }

    /// その表記を書いた場所で有効な型引数の名前の一覧。
    pub fn 有効な型引数名一覧(&self) -> &[String] {
        &self.有効な型引数名一覧
    }
}

impl プリミティブな事実 {
    /// 他の事実を自分の後ろへ併せる。抽出器が規則ごとに読んだ事実を1つへまとめるために使う。
    pub fn 併せる(&mut self, 他: Self) {
        self.型の定義一覧.extend(他.型の定義一覧);
        self.フィールドの型の表記一覧.extend(他.フィールドの型の表記一覧);
        self.エンティティの識別子の関連型一覧.extend(他.エンティティの識別子の関連型一覧);
        self.関数の役割の宣言一覧.extend(他.関数の役割の宣言一覧);
        self.関数の署名一覧.extend(他.関数の署名一覧);
    }

    /// 事実そのものが立てる節点。関数の役割の宣言と関数の署名が処理の節点を、型の定義が型の節点を立てる。関係に参加しない定義も節点として在る。
    pub fn 事実が立てる概念一覧(&self) -> Vec<設計概念> {
        let 処理 = self.関数の役割の宣言一覧.iter().map(|宣言| 宣言.処理.clone());
        let 署名の処理 = self.関数の署名一覧.iter().map(|署名| 署名.処理.clone());
        処理.chain(署名の処理).chain(self.型の定義一覧.iter().map(|定義| 定義.型.clone())).collect()
    }
}
