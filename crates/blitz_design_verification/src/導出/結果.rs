//! 導出の結果とは、定義の式をプリミティブな事実の上で評価して得た、関係と、関係の端点の節点と、導けなかった箇所の一覧のことである。
//!
//! 導けなかった箇所(導出の欠け)を結果へ載せるのは、型の表記を読めなかったことや定義をたどれなかったことを黙って落とさず、
//! 抽出器が自分の欠けの一覧へ写して数えられるようにするためである。どの欠けが関係そのものを失ったかは抽出器の区分が決め、
//! その区分が `関係を落とした抽出の欠落` を通って、欠けた事実に依存する関係の不在を未決定へ倒す。
//! 本体が成り立った束縛から頭の関係を1件導いてこの結果へ足す操作もここに置く。足す先の一覧(設計関係か保持する関係か)を選ぶのが頭の関係であり、
//! 足す操作が結果の一覧の形を知っているためである。

use super::束縛::束縛;
use super::規則::{導出の規則, 頭の関係};
use super::読めない理由::型の表記を読めない理由;
use crate::{事実の出どころ, 保持する関係, 導出の根拠, 抽出の出どころ, 設計概念, 設計関係};

/// 定義の式を評価して得たもの。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct 導出の結果 {
    /// 導いた関係の端点の節点。同じ節点が2度現れてよく、重複のまとめはグラフの組み立てが行う。
    pub 端点の概念一覧: Vec<設計概念>,
    /// 導いた設計関係。
    pub 設計関係一覧: Vec<設計関係>,
    /// 導いた保持する関係。
    pub 保持する関係一覧: Vec<保持する関係>,
    /// 規則の本体を評価する途中で導けなかった箇所。
    pub 欠け一覧: Vec<導出の欠け>,
}

/// 規則の本体を評価する途中で、型の表記から型を名指せなかった1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 導出の欠け {
    /// その表記が書かれていた場所。
    pub 出どころ: 事実の出どころ,
    /// 名指せなかった理由。
    pub 理由: 導出の欠けの理由,
}

/// 型の表記から型を名指せなかった理由。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 導出の欠けの理由 {
    /// 定義の式がその表記を読めない。関係そのものを導けない。
    型の表記を読めない(型の表記を読めない理由),
    /// 表記が、それを書いた場所で有効な型引数の名前である。実在しない設計概念の節点を作らないために関係を導かない。
    型引数である {
        /// 一致した型引数の名前。
        型引数名: String,
    },
    /// 型の定義をたどれず、節点のモジュールパスを空にした。関係は導き、節点も落とさない。
    定義のモジュールパスを解決できなかった {
        /// 定義を探した名前。フレーム型なら座標系を落とした名前である。
        型名: String,
    },
}

impl 導出の結果 {
    /// 本体が成り立った束縛1つから頭の関係を1件導き、その両端の節点とともにこの結果へ足す。
    pub(super) fn 規則の頭を足す(&mut self, 規則: &導出の規則, 束縛: &束縛) {
        let (Some((主語, 目的語)), Some((_, 表記の出どころ))) = (束縛.主語と目的語(), 束縛.表記()) else {
            panic!("規則「{}」の本体が頭の主語と目的語と表記を当てていない: 定義の式の規則は本体で頭の変数を全部当てるという不変条件が破れた", 規則.名前);
        };
        let 出どころ = 抽出の出どころ {
            パス: 表記の出どころ.パス.clone(),
            行番号: 表記の出どころ.行番号,
            構文: 規則.構文,
        };
        let 根拠 = 導出の根拠::生成する(規則.名前, 束縛.使った事実().to_vec());
        self.端点の概念一覧.extend([設計概念::参照から生成する(主語.clone()), 設計概念::参照から生成する(目的語.clone())]);
        match 規則.頭 {
            頭の関係::設計関係(種類) => self.設計関係一覧.push(設計関係 {
                主語: 主語.clone(),
                種類,
                目的語: 目的語.clone(),
                出どころ,
                根拠,
            }),
            頭の関係::保持する => self.保持する関係一覧.push(保持する関係 {
                主語: 主語.clone(),
                目的語: 目的語.clone(),
                出どころ,
                根拠,
            }),
        }
    }
}
