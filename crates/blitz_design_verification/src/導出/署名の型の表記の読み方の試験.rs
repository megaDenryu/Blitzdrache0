//! 署名の型の表記の読み方の試験。フィールドの読み方で読めない形(参照・`Result`・意味型・組・スライス・`impl`・`dyn`・寿命だけの型引数)から名指す型とトレイトを採ることと、
//! 型の引数を持たない標準ライブラリの型を名指さないことと、関数ポインタ・クロージャの引数と戻り値を読むことと、パスの修飾を修飾と名前に分けることと、
//! そのまま返すの範囲が包みとトレイトの中を読まないことを固定する。

use super::署名の型の表記の読み方::{署名の型の表記の読み取り, 署名の型の表記を読む, 署名の読み通す範囲};
use super::{型の表記の読み取り, 型の表記を読む};

// 包みとトレイトの中まで読んだ答えを、型は `型:名前`、トレイトは `トレイト:名前`、修飾された名前は `修飾:修飾|名前`、読めない表記は `読めない:呼び名` の文字列にして並べる。
fn 読んで並べる(表記: &str) -> Vec<String> {
    範囲を決めて読んで並べる(表記, 署名の読み通す範囲::包みとトレイトの中まで)
}

fn 範囲を決めて読んで並べる(表記: &str, 範囲: 署名の読み通す範囲) -> Vec<String> {
    署名の型の表記を読む(表記, 範囲)
        .into_iter()
        .map(|読み取り| match 読み取り {
            署名の型の表記の読み取り::型(型) => format!("型:{}", 型.同一性の名前()),
            署名の型の表記の読み取り::トレイト(トレイト) => format!("トレイト:{}", トレイト.同一性の名前()),
            署名の型の表記の読み取り::修飾された名前 { 修飾, 名前, .. } => format!("修飾:{修飾}|{}", 名前.同一性の名前()),
            署名の型の表記の読み取り::読めない(理由) => format!("読めない:{}", 理由.種別の呼び名()),
        })
        .collect()
}

#[test]
fn 参照と寿命を落として型を読む() {
    assert_eq!(読んで並べる("&'a mut 旅行者の現在地"), vec!["型:旅行者の現在地"]);
}

#[test]
fn 結果の型と組とスライスから複数の型を読む() {
    assert_eq!(読んで並べる("Result<旅行者の現在地, 歩行の失敗>"), vec!["型:旅行者の現在地", "型:歩行の失敗"]);
    assert_eq!(読んで並べる("(次の状態, Vec<出来事>)"), vec!["型:次の状態", "型:出来事"]);
    assert_eq!(読んで並べる("&[旅行者の現在地]"), vec!["型:旅行者の現在地"]);
    assert_eq!(読んで並べる("Option<Result<旅程, 失敗>>"), vec!["型:旅程", "型:失敗"]);
}

#[test]
fn プリミティブと単位型は何も名指さない() {
    assert!(読んで並べる("()").is_empty());
    assert!(読んで並べる("&str").is_empty());
    assert!(読んで並べる("Result<(), 失敗>") == vec!["型:失敗"]);
}

#[test]
fn implとdynの境界からトレイトを読み寿命の境界は読まない() {
    assert_eq!(読んで並べる("impl 世界の形 + 'a"), vec!["トレイト:世界の形"]);
    assert_eq!(読んで並べる("&mut dyn 世界の形"), vec!["トレイト:世界の形"]);
}

#[test]
fn 意味型の型の引数を読み通す() {
    assert_eq!(読んで並べる("Result<遷移成功結果<居場所, 出来事>, 遷移失敗結果<居場所, 失敗>>"), vec!["型:居場所", "型:出来事", "型:居場所", "型:失敗"]);
    assert_eq!(読んで並べる("問い合わせを伴う遷移の結果<状態, 観測, 失敗>"), vec!["型:状態", "型:観測", "型:失敗"]);
}

#[test]
fn implの境界のトレイトの型の引数と関連型の指定を読む() {
    assert_eq!(読んで並べる("impl Iterator<Item = (&経路Id, &予定)> + '_"), vec!["トレイト:Iterator", "型:経路Id", "型:予定"]);
    assert_eq!(読んで並べる("impl std::fmt::Display"), Vec::<String>::new());
}

#[test]
fn 寿命だけの型引数を落とし型の引数を持たない標準ライブラリの型は名指さない() {
    assert_eq!(読んで並べる("経路Ref<'_>"), vec!["型:経路Ref"]);
    assert!(読んで並べる("&mut std::fmt::Formatter<'_>").is_empty());
    assert!(読んで並べる("std::fmt::Result").is_empty());
    assert_eq!(読んで並べる("std::collections::HashMap<鍵, 値>"), vec!["読めない:型の表記が剥がす包みでないジェネリクスである"]);
}

#[test]
fn 関数ポインタとクロージャのトレイトから引数と戻り値の型を読む() {
    assert_eq!(読んで並べる("fn(&地図, u8) -> 居場所"), vec!["型:地図", "型:居場所"]);
    assert_eq!(読んで並べる("impl Fn(状態) -> Option<状態> + 'a"), vec!["型:状態", "型:状態"]);
    assert_eq!(読んで並べる("&mut dyn FnMut(fn(u8) -> 経路)"), vec!["型:経路"]);
    assert_eq!(読んで並べる("impl std::ops::FnOnce()"), Vec::<String>::new());
}

#[test]
fn パスの修飾が付いた名前は修飾と名前に分けて答える() {
    assert_eq!(読んで並べる("fmt::Result"), vec!["修飾:fmt|Result"]);
    assert_eq!(読んで並べる("Self::関連型"), vec!["修飾:Self|関連型"]);
    assert_eq!(読んで並べる("&crate::a::居場所"), vec!["修飾:crate::a|居場所"]);
    assert_eq!(読んで並べる("impl fmt::Display"), vec!["修飾:fmt|Display"]);
    assert_eq!(読んで並べる("blitz_math::変位<blitz_math::ワールド>"), vec!["修飾:blitz_math|変位<ワールド>"]);
    assert_eq!(読んで並べる("変位<blitz_math::ワールド>"), vec!["型:変位<ワールド>"]);
    assert_eq!(読んで並べる("a::Handle<メッシュ>"), vec!["読めない:型の表記が剥がす包みでないジェネリクスである"]);
}

#[test]
fn 値そのものと成分だけの範囲は包みとトレイトと関数の型の中を読まない() {
    let 成分だけ = |表記| 範囲を決めて読んで並べる(表記, 署名の読み通す範囲::値そのものと成分だけ);
    assert_eq!(成分だけ("Result<(居場所, 出来事), 失敗>"), vec!["型:居場所", "型:出来事", "型:失敗"]);
    assert_eq!(成分だけ("遷移成功結果<居場所, 出来事>"), vec!["型:居場所", "型:出来事"]);
    assert_eq!(成分だけ("Box<居場所>"), vec!["型:居場所"]);
    for 読まない表記 in ["Vec<居場所>", "Option<居場所>", "&[居場所]", "impl Iterator<Item = 居場所>", "fn() -> 居場所"] {
        assert!(成分だけ(読まない表記).is_empty(), "{読まない表記}");
    }
}

