//! 署名の型の表記の読み方の試験。フィールドの読み方で読めない形(参照・`Result`・組・スライス・`impl`・`dyn`)から名指す型とトレイトを採ることと、
//! 関数ポインタ・クロージャ・関連型を読めない表記として答えることを固定する。

use super::署名の型の表記の読み方::{署名の型の表記の読み取り, 署名の型の表記を読む};
use super::{型の表記の読み取り, 型の表記を読む};

// 読んだ答えを、型は `型:名前`、トレイトは `トレイト:名前`、読めない表記は `読めない:呼び名` の文字列にして並べる。
fn 読んで並べる(表記: &str) -> Vec<String> {
    署名の型の表記を読む(表記)
        .into_iter()
        .map(|読み取り| match 読み取り {
            署名の型の表記の読み取り::型(型) => format!("型:{}", 型.同一性の名前()),
            署名の型の表記の読み取り::トレイト(トレイト) => format!("トレイト:{}", トレイト.同一性の名前()),
            署名の型の表記の読み取り::読めない(理由) => format!("読めない:{}", 理由.種別の呼び名()),
        })
        .collect()
}

#[test]
fn 参照と寿命を落として型を読む() {
    assert_eq!(読んで並べる("&'a mut 旅行者の現在地"), vec!["型:旅行者の現在地"]);
}

#[test]
fn 結果の型と組とスライスから複数の型を読む() {
    assert_eq!(読んで並べる("Result<旅行者の現在地, 歩行の失敗>"), vec!["型:旅行者の現在地", "型:歩行の失敗"]);
    assert_eq!(読んで並べる("(次の状態, Vec<出来事>)"), vec!["型:次の状態", "型:出来事"]);
    assert_eq!(読んで並べる("&[旅行者の現在地]"), vec!["型:旅行者の現在地"]);
    assert_eq!(読んで並べる("Option<Result<旅程, 失敗>>"), vec!["型:旅程", "型:失敗"]);
}

#[test]
fn プリミティブと単位型は何も名指さない() {
    assert!(読んで並べる("()").is_empty());
    assert!(読んで並べる("&str").is_empty());
    assert!(読んで並べる("Result<(), 失敗>") == vec!["型:失敗"]);
}

#[test]
fn implとdynの境界からトレイトを読み寿命の境界は読まない() {
    assert_eq!(読んで並べる("impl 世界の形 + 'a"), vec!["トレイト:世界の形"]);
    assert_eq!(読んで並べる("&mut dyn 世界の形"), vec!["トレイト:世界の形"]);
}

#[test]
fn 関数ポインタとクロージャと関連型は読めない表記である() {
    assert_eq!(読んで並べる("fn(u8) -> u8"), vec!["読めない:型の表記がRustのパスでない"]);
    assert_eq!(読んで並べる("impl Fn(u8) -> u8"), vec!["読めない:型の表記がRustのパスでない"]);
    assert_eq!(読んで並べる("Self::関連型"), vec!["読めない:型の表記にパスの修飾がある"]);
}

// フィールドの読み方は変わらない。変わると保持するの定義が変わる。
#[test]
fn フィールドの読み方は結果の型も参照も従来どおり読む() {
    assert!(matches!(型の表記を読む("Result<旅程, 失敗>"), 型の表記の読み取り::保証範囲の外(_)));
}
