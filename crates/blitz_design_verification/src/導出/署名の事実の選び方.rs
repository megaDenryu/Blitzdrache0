//! 関数の署名の事実を、規則の本体の事実の原子で選ぶ工程。受け取るのは事実の原子と束縛、返すのは原子が当てた束縛の並びである。
//! 1件の署名から、引数の数だけ束縛が分かれる(`署名の引数を持つ`)。所有者の種類が原子と合わない署名と、戻り値を持たない署名と、
//! 受け手を選ぶ原子に対して受け手を持たない署名からは束縛を作らない。
//! 所有者がトレイトの署名は、関数とトレイトの両方が節点であり、表記を当てずに2つの概念を当てる(`束縛::事実から2つの概念を当てる`)。

use super::束縛::束縛;
use super::規則の本体の原子::事実の原子;
use super::関数の署名の事実の定義::{受け手の種類, 関数の所有者, 関数の署名の事実};

impl 関数の署名の事実 {
    /// 署名の事実を選ぶ原子でこの事実1件を選んだときの束縛の並び。署名の事実を選ばない原子では空である。
    pub(super) fn 原子で当てた束縛一覧(&self, 原子: 事実の原子, 束縛: &束縛) -> Vec<束縛> {
        let 処理 = self.処理.参照を組む();
        let 受け手を持つ = self.受け手 != 受け手の種類::無し;
        match 原子 {
            事実の原子::署名の所有者の型を持つ { 処理: 変数 } => match &self.所有者 {
                関数の所有者::型(表記) => 束縛.事実から当てる(変数, 処理, 表記.clone(), &self.出どころ).into_iter().collect(),
                関数の所有者::自由関数 | 関数の所有者::トレイト(_) => Vec::new(),
            },
            事実の原子::署名の所有者のトレイトを持つ { 処理: 変数, トレイト } => match &self.所有者 {
                関数の所有者::トレイト(参照) => 束縛.事実から2つの概念を当てる([(変数, 処理), (トレイト, 参照.clone())], &self.出どころ).into_iter().collect(),
                関数の所有者::自由関数 | 関数の所有者::型(_) => Vec::new(),
            },
            事実の原子::署名の受け手の型を持つ { 処理: 変数 } => match &self.所有者 {
                関数の所有者::型(表記) if 受け手を持つ => 束縛.事実から当てる(変数, 処理, 表記.clone(), &self.出どころ).into_iter().collect(),
                関数の所有者::型(_) | 関数の所有者::自由関数 | 関数の所有者::トレイト(_) => Vec::new(),
            },
            事実の原子::署名の受け手のトレイトを持つ { 処理: 変数, トレイト } => match &self.所有者 {
                関数の所有者::トレイト(参照) if 受け手を持つ => 束縛.事実から2つの概念を当てる([(変数, 処理), (トレイト, 参照.clone())], &self.出どころ).into_iter().collect(),
                関数の所有者::トレイト(_) | 関数の所有者::自由関数 | 関数の所有者::型(_) => Vec::new(),
            },
            事実の原子::署名の引数を持つ { 処理: 変数 } => self.引数の表記一覧.iter().filter_map(|表記| 束縛.事実から当てる(変数, 処理.clone(), 表記.clone(), &self.出どころ)).collect(),
            事実の原子::署名の戻り値を持つ { 処理: 変数 } => self.戻り値の表記.iter().filter_map(|表記| 束縛.事実から当てる(変数, 処理.clone(), 表記.clone(), &self.出どころ)).collect(),
            事実の原子::フィールドの型の表記を持つ { .. } | 事実の原子::エンティティの識別子の関連型を持つ { .. } | 事実の原子::役割の型引数を持つ { .. } => Vec::new(),
        }
    }
}
