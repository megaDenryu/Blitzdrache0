//! 規則の本体の原子 `表記が型を名指す` と `所有者の表記が型を名指す` を1つの束縛へ当てる工程。受け取るのは束縛と当てる変数と表記の読み方、返すのは成り立った束縛か、読めなかった欠けである。
//! 2つの原子は表記の読み方だけが違う(フィールドの読み方と、実装の対象の型の読み方)ため、読み方を純粋な関数の値として受け取る。
//!
//! 表記の読み取りは5つに分かれる。プリミティブと値を持たない型は設計概念でないため、欠けにも数えず黙って外す(外す条件を書き下せる)。
//! 読めない表記と、表記を書いた場所の型引数の名前は、関係を導かずに欠けとして返す。名指せた型は、定義の探索の口へ定義の在り処を問い、
//! たどれなければモジュールパスを空にした節点を当てたうえで欠けを1件返す。節点を落とさないのは、落とすと「関係が無い」と読まれ偽の反証が出るためである。
//! 欠けには、空の節点を当てた変数が頭の端点か本体の途中かを書く。本体の途中の変数では空の節点のために頭の関係ごと落ちうるため、抽出器がその関係の答えを弱める。
//! 本体の途中かは、当てた変数をその後の原子(事実の原子の結合か、分類の問い)が使うかで決める。変数の名前(経由する概念か、頭の主語か目的語か)で決めないのは、
//! 頭の主語か目的語を表記から当ててから後の事実の原子で結合する規則を足したとき、その変数の定義をたどれないことが頭の関係ごと落とすのに頭の端点と数えられ、穴が再び開くためである。
//! 定義は座標系を落とした名前で探し、節点の名前には座標系を含める。
//! 名指した型を当てる変数は、先の原子がまだ当てていない変数である。当たっている変数へ当てようとしたら、黙って束縛を落とさず規則の並びの不変条件の破れとして止める。

use super::プリミティブな事実の定義::型の表記;
use super::型の名前の定義の探索の定義::{修飾の無い名前の定義を探した結果, 型の名前の定義の探索};
use super::型の表記の読み方::{型の表記の読み取り, 型の表記を読む};
use super::導出の結果の定義::{名指せなかった変数の位置, 導出の欠け, 導出の欠けの理由};
use super::所有者の型の表記の読み方::所有者の型の表記を読む;
use super::束縛::束縛;
use super::表記が名指す型の定義::表記が名指す型;
use super::規則の本体の原子::概念の変数;
use super::評価::{原子の答え, 評価の工程};
use crate::{Rustの項目の種類, 事実の出どころ, 設計概念の識別子, 設計概念への参照};

impl<探索: 型の名前の定義の探索> 評価の工程<'_, 探索> {
    /// 束縛が当てた表記をフィールドの読み方で読み、名指す型をその変数へ当てる(`表記が型を名指す`)。
    pub(super) fn 名指す型を当てる(&self, 束縛: &束縛, 変数: 概念の変数) -> 原子の答え {
        self.読み方で名指す型を当てる(束縛, 変数, 型の表記を読む)
    }

    /// 束縛が当てた実装の対象の型の表記を所有者の読み方で読み、関数を持つ型をその変数へ当てる(`所有者の表記が型を名指す`)。
    pub(super) fn 所有者の型を当てる(&self, 束縛: &束縛, 変数: 概念の変数) -> 原子の答え {
        self.読み方で名指す型を当てる(束縛, 変数, 所有者の型の表記を読む)
    }

    // 束縛が当てた表記をその読み方で読み、名指す型をその変数へ当てる。表記が当たっていない束縛は、規則の並びの不変条件が破れている。
    fn 読み方で名指す型を当てる(&self, 束縛: &束縛, 変数: 概念の変数, 読み方: fn(&str) -> 型の表記の読み取り) -> 原子の答え {
        let (表記, 出どころ) = 当てた表記(束縛);
        let 名指す型 = match 読み方(表記.書かれた文字列()) {
            型の表記の読み取り::プリミティブである | 型の表記の読み取り::値を持たない型である => return 原子の答え::default(),
            型の表記の読み取り::保証範囲の外(理由) => return self.欠けの答え(出どころ, 導出の欠けの理由::型の表記を読めない(理由)),
            型の表記の読み取り::設計概念である(名指す型) => 名指す型,
        };
        if let Some(型引数名) = 名指す型.宣言の型引数と一致する名前(表記.有効な型引数名一覧()) {
            return self.欠けの答え(出どころ, 導出の欠けの理由::型引数である { 型引数名 });
        }
        self.名指した型を当てる(束縛, 変数, &名指す型, Rustの項目の種類::型)
    }

    /// 名指した型かトレイトの定義の在り処を定義の探索の口へ問い、その節点を変数へ当てた束縛を返す。定義をたどれなければモジュールパスを空にした節点を当て、欠けを1件添える。
    /// 標準ライブラリの項目なら、修飾の付いた名前と同じく関係を導かない。
    pub(super) fn 名指した型を当てる(&self, 束縛: &束縛, 変数: 概念の変数, 名指す型: &表記が名指す型, 種類: Rustの項目の種類) -> 原子の答え {
        let (_, 出どころ) = 当てた表記(束縛);
        match self.探索.修飾の無い名前の定義を探す(名指す型.定義を探す名前(), 種類, 出どころ) {
            修飾の無い名前の定義を探した結果::定義がある { モジュールパス } => self.在り処の分かった型を当てる(束縛, 変数, 名指す型, 種類, Some(モジュールパス)),
            修飾の無い名前の定義を探した結果::標準ライブラリの項目である => 原子の答え::default(),
            修飾の無い名前の定義を探した結果::定義をたどれない => self.在り処の分かった型を当てる(束縛, 変数, 名指す型, 種類, None),
        }
    }

    /// 定義の探索の口が答えた定義の在り処(たどれなければ無し)で、名指した型かトレイトの節点を変数へ当てる。無しならモジュールパスを空にした節点を当て、欠けを1件添える。
    pub(super) fn 在り処の分かった型を当てる(&self, 束縛: &束縛, 変数: 概念の変数, 名指す型: &表記が名指す型, 種類: Rustの項目の種類, 在り処: Option<String>) -> 原子の答え {
        let (_, 出どころ) = 当てた表記(束縛);
        let (モジュールパス, 欠け一覧) = match 在り処 {
            Some(モジュールパス) => (モジュールパス, Vec::new()),
            None => {
                let 理由 = 導出の欠けの理由::定義のモジュールパスを求められなかった {
                    型名: 名指す型.定義を探す名前().to_string(),
                    変数の位置: self.名指せなかった変数の位置を決める(変数),
                };
                (String::new(), self.欠けの答え(出どころ, 理由).欠け一覧)
            }
        };
        let 参照 = 設計概念への参照::Rustの項目として生成する(設計概念の識別子::Rustの項目として生成する(&モジュールパス, &名指す型.同一性の名前()), 種類);
        原子の答え {
            束縛一覧: vec![束縛.空いている変数へ当てる(変数, 参照)],
            欠け一覧,
        }
    }

    /// 束縛を残さず、その理由の欠けを1件だけ持つ答え。欠けはいま当てている規則の頭の関係を持つ。
    pub(super) fn 欠けの答え(&self, 出どころ: &事実の出どころ, 理由: 導出の欠けの理由) -> 原子の答え {
        原子の答え {
            束縛一覧: Vec::new(),
            欠け一覧: vec![導出の欠け {
                出どころ: 出どころ.clone(),
                理由,
                導けなかった関係: self.規則.頭,
            }],
        }
    }

    // 変数を当てた原子より後ろの原子のどれかがその変数を使うなら本体の途中、どれも使わなければ頭の端点である。
    // 規則はどの変数も表記を読む原子で1度だけ当てる(`束縛::空いている変数へ当てる` がその不変条件を守る)ため、当てた原子は最初に現れたものである。
    fn 名指せなかった変数の位置を決める(&self, 変数: 概念の変数) -> 名指せなかった変数の位置 {
        let 本体 = &self.規則.本体;
        let Some(当てた位置) = 本体.iter().position(|原子| 原子.表記から当てる変数() == Some(変数)) else {
            panic!(
                "規則「{}」の本体に変数 {変数:?} を当てる `表記が型を名指す` が無いのに、その変数へ名指せなかった型を当てようとした: 評価器はその原子を当てるときだけこの工程を呼ぶという不変条件が破れた",
                self.規則.名前
            );
        };
        if 本体.iter().skip(当てた位置 + 1).any(|原子| 原子.変数を使うか(変数)) {
            名指せなかった変数の位置::本体の途中
        } else {
            名指せなかった変数の位置::頭の端点
        }
    }
}

/// 束縛が当てた型の表記と、その表記が書かれていた場所。表記を読む原子より前に表記を当てる事実の原子が無ければ、規則の並びの不変条件が破れている。
pub(super) fn 当てた表記(束縛: &束縛) -> (&型の表記, &事実の出どころ) {
    let Some((表記, 出どころ)) = 束縛.表記() else {
        panic!("表記を読む原子の前に表記を当てる事実の原子が無い: 定義の式の規則は事実の原子を先に置くという不変条件が破れた");
    };
    (表記, 出どころ)
}
