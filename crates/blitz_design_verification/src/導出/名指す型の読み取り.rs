//! 規則の本体の原子 `表記が型を名指す` を1つの束縛へ当てる工程。受け取るのは束縛と当てる変数、返すのは成り立った束縛か、読めなかった欠けである。
//!
//! 表記の読み取りは5つに分かれる。プリミティブと値を持たない型は設計概念でないため、欠けにも数えず黙って外す(外す条件を書き下せる)。
//! 読めない表記と、表記を書いた場所の型引数の名前は、関係を導かずに欠けとして返す。名指せた型は、解決の口へ定義の在り処を問い、
//! たどれなければモジュールパスを空にした節点を当てたうえで欠けを1件返す。節点を落とさないのは、落とすと「関係が無い」と読まれ偽の反証が出るためである。
//! 欠けには、空の節点を当てた変数が頭の端点か本体の途中かを書く。本体の途中の変数では空の節点のために頭の関係ごと落ちうるため、抽出器がその関係の答えを弱める。
//! 本体の途中かは、当てた変数をその後の原子(事実の原子の結合か、分類の問い)が使うかで決める。変数の名前(経由する概念か、頭の主語か目的語か)で決めないのは、
//! 頭の主語か目的語を表記から当ててから後の事実の原子で結合する規則を足したとき、その変数の未解決が頭の関係ごと落とすのに頭の端点と数えられ、穴が再び開くためである。
//! 定義は座標系を落とした名前で探し、節点の名前には座標系を含める。
//! 名指した型を当てる変数は、先の原子がまだ当てていない変数である。当たっている変数へ当てようとしたら、黙って束縛を落とさず規則の並びの不変条件の破れとして止める。

use super::型の名前の解決の定義::型の名前の解決;
use super::型の表記の読み方::{型の表記の読み取り, 型の表記を読む};
use super::導出の結果の定義::{名指せなかった変数の位置, 導出の欠け, 導出の欠けの理由};
use super::束縛::束縛;
use super::規則の本体の原子::{本体の原子, 概念の変数};
use super::評価::{原子の答え, 評価の工程};
use crate::{Rustの項目の種類, 設計概念の識別子, 設計概念への参照};

impl<解決: 型の名前の解決> 評価の工程<'_, 解決> {
    /// 束縛が当てた表記を読み、名指す型をその変数へ当てる。表記が当たっていない束縛は、規則の並びの不変条件が破れている。
    pub(super) fn 名指す型を当てる(&self, 束縛: &束縛, 変数: 概念の変数) -> 原子の答え {
        let Some((表記, 出どころ)) = 束縛.表記() else {
            panic!("`表記が型を名指す` の前に表記を当てる事実の原子が無い: 定義の式の規則は事実の原子を先に置くという不変条件が破れた");
        };
        let 欠けの答え = |理由| 原子の答え {
            束縛一覧: Vec::new(),
            欠け一覧: vec![導出の欠け {
                出どころ: 出どころ.clone(),
                理由,
                導けなかった関係: self.規則.頭,
            }],
        };
        let 名指す型 = match 型の表記を読む(表記.綴り()) {
            型の表記の読み取り::プリミティブである | 型の表記の読み取り::値を持たない型である => return 原子の答え::default(),
            型の表記の読み取り::保証範囲の外(理由) => return 欠けの答え(導出の欠けの理由::型の表記を読めない(理由)),
            型の表記の読み取り::設計概念である(名指す型) => 名指す型,
        };
        if let Some(型引数名) = 名指す型.宣言の型引数と一致する名前(表記.有効な型引数名一覧()) {
            return 欠けの答え(導出の欠けの理由::型引数である { 型引数名 });
        }
        let (モジュールパス, 欠け一覧) = match self.解決.定義のモジュールパスを求める(名指す型.定義を探す名前(), 出どころ) {
            Some(モジュールパス) => (モジュールパス, Vec::new()),
            None => {
                let 理由 = 導出の欠けの理由::定義のモジュールパスを解決できなかった {
                    型名: 名指す型.定義を探す名前().to_string(),
                    変数の位置: self.名指せなかった変数の位置を決める(変数),
                };
                (
                    String::new(),
                    vec![導出の欠け {
                        出どころ: 出どころ.clone(),
                        理由,
                        導けなかった関係: self.規則.頭,
                    }],
                )
            }
        };
        let 参照 = 設計概念への参照::Rustの項目として生成する(設計概念の識別子::Rustの項目として生成する(&モジュールパス, &名指す型.同一性の名前()), Rustの項目の種類::型);
        原子の答え {
            束縛一覧: vec![束縛.空いている変数へ当てる(変数, 参照)],
            欠け一覧,
        }
    }

    // 変数を当てた原子より後ろの原子のどれかがその変数を使うなら本体の途中、どれも使わなければ頭の端点である。
    // 規則はどの変数も `表記が型を名指す` で1度だけ当てる(`束縛::空いている変数へ当てる` がその不変条件を守る)ため、当てた原子は最初に現れたものである。
    fn 名指せなかった変数の位置を決める(&self, 変数: 概念の変数) -> 名指せなかった変数の位置 {
        let 本体 = &self.規則.本体;
        let Some(当てた位置) = 本体.iter().position(|原子| *原子 == 本体の原子::表記が型を名指す { 型: 変数 }) else {
            panic!(
                "規則「{}」の本体に変数 {変数:?} を当てる `表記が型を名指す` が無いのに、その変数へ名指せなかった型を当てようとした: 評価器はその原子を当てるときだけこの工程を呼ぶという不変条件が破れた",
                self.規則.名前
            );
        };
        if 本体.iter().skip(当てた位置 + 1).any(|原子| 原子.変数を使うか(変数)) {
            名指せなかった変数の位置::本体の途中
        } else {
            名指せなかった変数の位置::頭の端点
        }
    }
}
