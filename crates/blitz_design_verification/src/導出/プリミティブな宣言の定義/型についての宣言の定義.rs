//! 型についてのプリミティブな宣言の1件ずつの型。型の定義と、フィールドの型の表記と、エンティティの識別子の関連型の3つである。
//! 3つを同じファイルに置くのは、どれも `struct`・`enum`・`impl Mエンティティ` という型の宣言から読む宣言であり、
//! 型のノードか型への参照と、宣言の出どころを持つ同じ形の値だからである。関数の役割の宣言は処理の宣言であるため別に置く。

use super::型の表記;
use crate::{宣言の出どころ, 設計概念の識別用情報, 設計概念ノード};

/// `struct`・`enum` の宣言1件。その型のノードを立てる。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 型の定義 {
    型: 設計概念ノード, // 宣言した型のノード
    出どころ: 宣言の出どころ,
}

/// `struct`・`enum` のフィールド1つの型の表記。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct フィールドの型の表記の宣言 {
    持ち主: 設計概念の識別用情報, // フィールドを持つ型への参照
    表記: 型の表記,
    出どころ: 宣言の出どころ,
}

/// `impl Mエンティティ for 型 { type 識別子 = 表記; }` の1件。出どころは関連型の行を指す。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct エンティティの識別子の関連型の宣言 {
    エンティティ: 設計概念の識別用情報, // `Mエンティティ` を実装した型への参照
    表記: 型の表記,                     // 関連型 `識別子` の右辺の表記
    出どころ: 宣言の出どころ,
}

impl 型の定義 {
    /// 宣言した型のノードと、宣言の出どころから組む。
    pub fn 生成する(型: 設計概念ノード, 出どころ: 宣言の出どころ) -> Self {
        Self { 型, 出どころ }
    }

    /// 宣言した型のノードを読む。
    pub fn 型(&self) -> &設計概念ノード {
        &self.型
    }

    /// この1件がどのソースのどの行から出たかを読む。
    pub fn 出どころ(&self) -> &宣言の出どころ {
        &self.出どころ
    }
}

impl フィールドの型の表記の宣言 {
    /// フィールドを持つ型への参照と、フィールドの型の表記と、宣言の出どころから組む。
    pub fn 生成する(持ち主: 設計概念の識別用情報, 表記: 型の表記, 出どころ: 宣言の出どころ) -> Self {
        Self { 持ち主, 表記, 出どころ }
    }

    /// フィールドを持つ型への参照を読む。
    pub fn 持ち主(&self) -> &設計概念の識別用情報 {
        &self.持ち主
    }

    /// フィールドの型の表記を読む。
    pub fn 表記(&self) -> &型の表記 {
        &self.表記
    }

    /// この1件がどのソースのどの行から出たかを読む。
    pub fn 出どころ(&self) -> &宣言の出どころ {
        &self.出どころ
    }
}

impl エンティティの識別子の関連型の宣言 {
    /// `Mエンティティ` を実装した型への参照と、関連型 `識別子` の右辺の表記と、関連型の行の出どころから組む。
    pub fn 生成する(エンティティ: 設計概念の識別用情報, 表記: 型の表記, 出どころ: 宣言の出どころ) -> Self {
        Self { エンティティ, 表記, 出どころ }
    }

    /// `Mエンティティ` を実装した型への参照を読む。
    pub fn エンティティ(&self) -> &設計概念の識別用情報 {
        &self.エンティティ
    }

    /// 関連型 `識別子` の右辺の表記を読む。
    pub fn 表記(&self) -> &型の表記 {
        &self.表記
    }

    /// この1件がどのソースのどの行から出たかを読む。関連型の行を指す。
    pub fn 出どころ(&self) -> &宣言の出どころ {
        &self.出どころ
    }
}
