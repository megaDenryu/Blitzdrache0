//! 関数の役割の宣言とは、`const _: M状態遷移関数<..> = M状態遷移関数::生成する(所有者::関数);` の形で、関数へ役割を与える宣言のことである。
//! 型引数の書かれた文字列を位置の順に並べたまま運び、どの位置が何を変換用の素材にするかは定義の式が決める。

use super::型の表記;
use crate::{宣言の出どころ, 設計概念ノード, 関数の役割};

/// 関数の役割の宣言1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 関数の役割の宣言 {
    処理: 設計概念ノード, // 役割に包まれた関数のノード。種類は処理である
    役割: 関数の役割,
    型引数の表記一覧: Vec<型の表記>, // 役割の型引数の表記を位置の順に並べる
    出どころ: 宣言の出どころ,
}

impl 関数の役割の宣言 {
    /// 役割に包まれた関数のノードと、宣言した役割と、型引数の表記を位置の順に並べた一覧と、宣言の出どころから組む。
    pub fn 生成する(処理: 設計概念ノード, 役割: 関数の役割, 型引数の表記一覧: Vec<型の表記>, 出どころ: 宣言の出どころ) -> Self {
        Self {
            処理, 役割, 型引数の表記一覧, 出どころ
        }
    }

    /// 役割に包まれた関数のノードを読む。
    pub fn 処理(&self) -> &設計概念ノード {
        &self.処理
    }

    /// 宣言した役割を読む。
    pub fn 役割(&self) -> 関数の役割 {
        self.役割
    }

    /// 役割の型引数の表記を位置の順に読む。
    pub fn 型引数の表記一覧(&self) -> &[型の表記] {
        &self.型引数の表記一覧
    }

    /// この1件がどのソースのどの行から出たかを読む。
    pub fn 出どころ(&self) -> &宣言の出どころ {
        &self.出どころ
    }
}
