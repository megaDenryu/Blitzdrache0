//! 命題が問う答えの試験。原子と対象集合と結合を辿って答えを重ねずに並べることと、欠落の件のうち問う答えを弱めるものだけを数えることを固定する。

use crate::{
    プリミティブな関係の種類, 原子命題, 命題, 対象集合, 束縛変数, 欠落が弱める答え, 落とした理由ごとの件数, 設計概念への参照, 設計関係の結び付き方, 関係を落とした抽出の欠落, 関数の引数と戻り値の役目, 非空の命題一覧, 項
};

fn 型(名前: &str) -> 項 {
    項::名指した概念(設計概念への参照::型として生成する("blitz_esca::旅行者", 名前))
}

#[test]
fn 量化は対象集合の列挙が依る答えと本体の原子の答えを重ねずに並べる() {
    let 型の変数 = 束縛変数::生成する("型");
    let 変換用の素材にする = 命題::原子から組む(原子命題::設計関係が在る {
        主語: 型("処理"),
        結び付き方: 関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す(),
        目的語: 項::束縛変数(型の変数.clone()),
    });
    let 保持する = 命題::原子から組む(原子命題::プリミティブな関係の経路が在る {
        主語: 型("容器"),
        種類: プリミティブな関係の種類::保持する,
        目的語: 項::束縛変数(型の変数.clone()),
    });
    let 本体 = 命題::選言(非空の命題一覧::先頭と残りから生成する(変換用の素材にする.clone(), vec![保持する, 変換用の素材にする]));
    let 全称 = 命題::全称を組む(型の変数, 対象集合::マーカーを持つ設計概念 { マーカー名: "Mコマンド".to_string() }, 本体);
    assert_eq!(
        全称.問う答え一覧(),
        vec![
            欠落が弱める答え::付いているマーカー,
            欠落が弱める答え::設計関係(関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す()),
            欠落が弱める答え::プリミティブな関係(プリミティブな関係の種類::保持する)
        ]
    );
}

#[test]
fn 振る舞いの原子と到達可能な範囲はグラフの答えに依らない() {
    let 到達 = 命題::原子から組む(原子命題::到達可能である { 状態: 型("状態") });
    assert!(到達.問う答え一覧().is_empty());
    assert!(対象集合::到達可能な状態.列挙が依る答え一覧().is_empty());
}

// 反証: 欠落の合計を数えると、どの命題も問わない答え(問わない種類の設計関係)だけを弱める件で合否が落ちる。
#[test]
fn 問う答えを弱める件だけを数える() {
    let 件 = |説明: &str, 件数, 答え| 落とした理由ごとの件数 {
        理由の説明: 説明.to_string(),
        件数,
        弱める答え一覧: vec![答え],
    };
    let 欠落 = 関係を落とした抽出の欠落::生成する(
        vec![
            件("エンティティの識別子の関連型を読めない", 5, 欠落が弱める答え::設計関係(設計関係の結び付き方::識別する)),
            件("型の表記を読めない", 2, 欠落が弱める答え::設計関係(関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す())),
        ],
        &[],
    );
    assert_eq!(
        欠落.答えを弱める件の件数(&[欠落が弱める答え::設計関係(関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す()), 欠落が弱める答え::付いているマーカー]),
        2
    );
    assert_eq!(欠落.合計の件数(), 7);
}
