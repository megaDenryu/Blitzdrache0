//! 設計解釈マーカーの宣言の一覧と各型に付いているマーカーの一覧。
//!
//! 各型に付いているマーカーの一覧とは、設計関係グラフのノードごとに、その型が持つ付いているマーカーを引ける索引のことである。付いているマーカーとは、型が実装した設計解釈マーカーの集合を、
//! 上位トレイトの宣言で閉じたもののことである(`M状態` を実装した型は `M不変データ` も持つ)。
//!
//! **閉包は設計解釈マーカーの宣言の一覧から計算する。** 公理(設計解釈マーカーどうしの一種であるという関係)の正本は上位トレイトの宣言であり、この型は公理の表を持たない。
//! **閉包は設計解釈マーカーだけを辿る。** 付いているマーカーは型が実装した設計解釈マーカーの集合であるため、`M不変データ: Clone` の `Clone` のような
//! 標準のトレイトは、上位トレイトの宣言に在っても付いているマーカーへ入れない。入れると、`マーカーを持つ` の問いが標準のトレイトの名前にも
//! 答えてしまい、マーカーの意味を問う原子が型の形を問う原子と区別できなくなる。
//! マーカーが付くのは、マーカーの実装の主語に立つ型だけである。トレイトにはマーカーが付かない。`trait M不変エンティティ: Mエンティティ` を
//! `Mエンティティ` を持つ概念として数えると、そのマーカーを実装した型が1件も無くても母集団へトレイトが入るためである。
//!
//! **付いているマーカーは設計関係への参加に数えない。** 付いているマーカーはエッジではないため、`設計関係グラフ::設計関係へ1つも参加していないか` はこの索引を読まない。
//! 参照: Issue #193「分類と公理」。

#[cfg(test)]
#[path = "各型に付いているマーカーの一覧の定義/各型に付いているマーカーの一覧の試験.rs"]
mod 各型に付いているマーカーの一覧の試験;
#[path = "各型に付いているマーカーの一覧の定義/設計解釈マーカーの宣言.rs"]
mod 設計解釈マーカーの宣言;

use std::collections::{HashMap, HashSet};

use crate::設計概念の識別用情報;

pub use 設計解釈マーカーの宣言::{マーカーの実装, 上位トレイトの宣言, 宣言の出どころ, 設計解釈マーカーの宣言の一覧};

/// 型ごとに、その型が持つマーカーの一覧を取得できる表。一覧には、直接付けたマーカーが含むマーカーも入れる(`M状態` を付けた型なら `M不変データ` も入る)。
#[derive(Debug, Clone, Default)]
pub struct 各型に付いているマーカーの一覧 {
    設計解釈マーカーの宣言の一覧: 設計解釈マーカーの宣言の一覧,
    型ごとに付いているマーカー: Vec<(設計概念の識別用情報, Vec<設計概念の識別用情報>)>, // マーカーの実装に型が初めて現れた順
    索引: HashMap<設計概念の識別用情報, usize>,                                         // 型から `型ごとに付いているマーカー` の添字を引く
    宣言に現れる参照: HashSet<設計概念の識別用情報>,                                    // マーカーの実装と上位トレイトの宣言の端点。設計解釈マーカーの一覧だけに在るものは入れない
}

impl 各型に付いているマーカーの一覧 {
    /// 設計解釈マーカーの宣言の一覧から、型ごとに付いているマーカーを上位トレイトの宣言で閉じて組む。
    pub(crate) fn 設計解釈マーカーの宣言の一覧から閉包を取って生成する(設計解釈マーカーの宣言の一覧: 設計解釈マーカーの宣言の一覧) -> Self {
        let 設計解釈マーカー: HashSet<設計概念の識別用情報> = 設計解釈マーカーの宣言の一覧.設計解釈マーカー一覧().iter().cloned().collect();
        let mut 上位の表: HashMap<&設計概念の識別用情報, Vec<&設計概念の識別用情報>> = HashMap::new();
        for 宣言 in 設計解釈マーカーの宣言の一覧
            .上位トレイトの宣言一覧()
            .iter()
            .filter(|宣言| 設計解釈マーカー.contains(&宣言.トレイト) && 設計解釈マーカー.contains(&宣言.上位トレイト))
        {
            上位の表.entry(&宣言.トレイト).or_default().push(&宣言.上位トレイト);
        }
        let mut 型ごとに付いているマーカー: Vec<(設計概念の識別用情報, Vec<設計概念の識別用情報>)> = Vec::new();
        let mut 索引 = HashMap::new();
        for 実装 in 設計解釈マーカーの宣言の一覧.マーカーの実装一覧().iter().filter(|実装| 設計解釈マーカー.contains(&実装.マーカー)) {
            let 添字 = *索引.entry(実装.型.clone()).or_insert_with(|| {
                型ごとに付いているマーカー.push((実装.型.clone(), Vec::new()));
                型ごとに付いているマーカー.len() - 1
            });
            let 付いているマーカー = &mut 型ごとに付いているマーカー[添字].1;
            for トレイト in 上位へ閉じる(&上位の表, &実装.マーカー) {
                if !付いているマーカー.contains(&トレイト) {
                    付いているマーカー.push(トレイト);
                }
            }
        }
        let 宣言に現れる参照 = 設計解釈マーカーの宣言の一覧
            .マーカーの実装一覧()
            .iter()
            .flat_map(|実装| [&実装.型, &実装.マーカー])
            .chain(設計解釈マーカーの宣言の一覧.上位トレイトの宣言一覧().iter().flat_map(|宣言| [&宣言.トレイト, &宣言.上位トレイト]))
            .cloned()
            .collect();
        Self {
            設計解釈マーカーの宣言の一覧,
            型ごとに付いているマーカー,
            索引,
            宣言に現れる参照,
        }
    }

    /// この索引を組んだ設計解釈マーカーの宣言の一覧。
    pub fn 設計解釈マーカーの宣言の一覧を貸す(&self) -> &設計解釈マーカーの宣言の一覧 {
        &self.設計解釈マーカーの宣言の一覧
    }

    /// その概念に付いているマーカー(上位トレイトの宣言で閉じたもの)。マーカーが付かない概念では空を返す。
    pub fn 概念に付いているマーカー(&self, 概念: &設計概念の識別用情報) -> &[設計概念の識別用情報] {
        self.索引.get(概念).map_or(&[], |添字| self.型ごとに付いているマーカー[*添字].1.as_slice())
    }

    /// その概念に付いているマーカー(上位トレイトの宣言で閉じたもの)が、そのトレイトを含むか。
    pub fn 付いているマーカーがトレイトを含むか(&self, 概念: &設計概念の識別用情報, トレイト: &設計概念の識別用情報) -> bool {
        self.概念に付いているマーカー(概念).contains(トレイト)
    }

    /// 付いているマーカー(上位トレイトの宣言で閉じたもの)にその名前のトレイトを含む概念の一覧。命題がマーカーを名前で名指すため、名前で照合する。
    pub fn 名前のトレイトが付いている概念一覧(&self, 名前: &str) -> Vec<&設計概念の識別用情報> {
        self.型ごとに付いているマーカー
            .iter()
            .filter(|(_, 付いているマーカー)| 付いているマーカー.iter().any(|トレイト| トレイト.識別子().名前() == 名前))
            .map(|(型, _)| 型)
            .collect()
    }

    /// その名前を持つ設計解釈マーカーの一覧。設計解釈マーカーでない名前には空を返す。命題がマーカーを名前で名指すため、名前で照合する。
    pub fn 名前の設計解釈マーカー一覧(&self, 名前: &str) -> Vec<&設計概念の識別用情報> {
        self.設計解釈マーカーの宣言の一覧.設計解釈マーカー一覧().iter().filter(|マーカー| マーカー.識別子().名前() == 名前).collect()
    }

    /// その参照が、設計解釈マーカーの宣言の一覧のどれかに型・マーカー・トレイト・上位トレイトとして現れるか。
    pub fn 宣言に現れるか(&self, 参照: &設計概念の識別用情報) -> bool {
        self.宣言に現れる参照.contains(参照)
    }
}

// 起点のトレイトと、起点から上位トレイトの宣言を辿って達するトレイトの全部。上位の表は設計解釈マーカーどうしの宣言だけを持つ。同じトレイトを2度は辿らない。
fn 上位へ閉じる(上位の表: &HashMap<&設計概念の識別用情報, Vec<&設計概念の識別用情報>>, 起点: &設計概念の識別用情報) -> Vec<設計概念の識別用情報> {
    let mut 達した: Vec<設計概念の識別用情報> = Vec::new();
    let mut 待ち = vec![起点];
    while let Some(いま) = 待ち.pop() {
        if 達した.contains(いま) {
            continue;
        }
        達した.push(いま.clone());
        待ち.extend(上位の表.get(いま).into_iter().flatten().copied());
    }
    達した
}
