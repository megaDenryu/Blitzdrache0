/// 原子命題が主語と目的語に取るもの。名指した概念そのままか、量化が当てる束縛変数である。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 項 {
    /// 設計概念を直に名指した項。
    名指した概念(設計概念の識別用情報),
    /// 量化が要素を当てる束縛変数の項。
    束縛変数(束縛変数),
}

/// それ以上分解しない最小の主張。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 原子命題 {
    /// 主語から目的語へその結び付き方の設計関係が1件でも在る。
    設計関係の有無命題(設計関係の有無命題),
    /// 主語から目的語へ、その結び付き方のエッジだけを辿って達する経路が在る。
    設計関係の経路の有無命題(設計関係の経路の有無命題),
    /// 主語から目的語へその種類のプリミティブな関係が1件でも在る。
    プリミティブな関係の有無命題(プリミティブな関係の有無命題),
    /// 主語から目的語へ、その種類のプリミティブな関係のエッジだけを辿って達する経路が在る。
    プリミティブな関係の経路の有無命題(プリミティブな関係の経路の有無命題),
    /// その型の付いているマーカーが、その名前の設計解釈マーカーを含む。
    マーカー保有命題(マーカー保有命題),
    /// その概念が主語としても目的語としても、設計関係に1件も参加していない。
    孤立命題(孤立命題),
    /// その状態遷移でそのイベントが成立する。振る舞いの原子命題である。
    発生命題(発生命題),
    /// 前状態へその入力を与えると後状態へ状態遷移する。振る舞いの原子命題である。
    状態遷移命題(状態遷移命題),
    /// その状態が初期状態から到達できる。振る舞いの原子命題である。
    到達可能性命題(到達可能性命題),
}

impl 項 {
    /// 束縛の割り当てを読んでこの項が指す設計概念の識別用情報を求める。当てられていない束縛変数では値なしを返す。
    pub fn 束縛の割り当てから設計概念の識別用情報を求める(&self, 割り当て: &束縛の割り当て) -> Option<設計概念の識別用情報> {
        match self {
            Self::名指した概念(参照) => Some(参照.clone()),
            Self::束縛変数(束縛) => 割り当て.束縛変数に当たる概念を求める(束縛).cloned(),
        }
    }

    /// 人が読む1行の表記。束縛変数は名前の前に `?` を付けて名指した概念と見分ける。
    pub fn 表記(&self) -> String {
        match self {
            Self::名指した概念(参照) => 参照.表記(),
            Self::束縛変数(束縛) => format!("?{}", 束縛.名前()),
        }
    }
}

impl 原子命題 {
    /// この原子命題が振る舞いの原子命題(構造の検証器が解かないもの)であるか。
    pub const fn 振る舞いの原子命題か(&self) -> bool {
        matches!(self, Self::発生命題(_) | Self::状態遷移命題(_) | Self::到達可能性命題(_))
    }

    /// 人が読む1行の表記。
    pub fn 表記(&self) -> String {
        match self {
            Self::設計関係の有無命題(問い) => 問い.表記(),
            Self::設計関係の経路の有無命題(問い) => 問い.表記(),
            Self::プリミティブな関係の有無命題(問い) => 問い.表記(),
            Self::プリミティブな関係の経路の有無命題(問い) => 問い.表記(),
            Self::マーカー保有命題(問い) => 問い.表記(),
            Self::孤立命題(問い) => 問い.表記(),
            Self::発生命題(問い) => 問い.表記(),
            Self::状態遷移命題(問い) => 問い.表記(),
            Self::到達可能性命題(問い) => 問い.表記(),
        }
    }
}
