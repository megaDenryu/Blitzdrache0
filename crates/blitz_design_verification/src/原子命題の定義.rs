//! 項と原子命題(Issue #173。層3のうち、それ以上分解しない最小の主張)。
//!
//! 原子命題の選択肢は、それぞれが名前を持つ1つの型を運ぶ。問いごとに持つ項の組が違い、
//! 名前の無いフィールドの並びのままでは、読み手も検証器もどの項が何の役かを選択肢の定義まで戻って読むことになるためである。
//!
//! **設計関係の語を原子命題の選択肢へ展開しない。** `設計関係の有無命題` が結び付き方を欄として持つ1つの選択肢で足り、
//! 展開すると関係の語を1つ足すたびに原子命題の選択肢と検証器の場合分けが1つずつ増える。
//! プリミティブな関係の語も同じ理由で展開しない。
//!
//! 後ろの3つ(`発生命題`・`状態遷移命題`・`到達可能性命題`)は振る舞いの原子命題であり、構造の検証器はこれを解かない。
//! 構造の検証器は偽で答えず `検証結果::未決定` で答える。解くのは有限全数の検証器である。
//! 参照: `_doc/設計/設計オントロジー.md` 第7節・第10節。

