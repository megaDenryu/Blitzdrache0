//! 有限全数の検証器が、原子命題と対象集合の解き手として答える実装。
//!
//! トレイトの実装を親のファイルから分けるのは、親が持つのは遷移モデルと網羅性の保持であり、
//! こちらが持つのは命題層の語彙(原子命題・対象集合)との対応だけであるためである(CLAUDE.md「切り出しの根拠義務」の1号)。
//! 論理の結合はここでも解かず、結合を解く工程へ渡す。列挙が名乗る網羅性は検証器が保持している網羅性をそのまま渡す。

use super::{列挙してよい対象の上限, 有限全数の検証器};
use crate::設計概念の識別子;
use crate::{列挙した対象, 原子と対象集合の解き手, 原子命題, 命題, 命題の検証器, 対象集合, 未決定の理由, 束縛の割り当て, 検証の方式, 検証結果, 結合を解く工程};

impl 原子と対象集合の解き手 for 有限全数の検証器 {
    fn 方式(&self) -> 検証の方式 {
        検証の方式::有限全数
    }

    fn 原子を解く(&self, 原子: &原子命題, 割り当て: &束縛の割り当て) -> 検証結果 {
        match 原子 {
            原子命題::発生する { 遷移, イベント } => {
                let (Some(遷移の概念), Some(出来事)) = (遷移.束縛の割り当てから設計概念の識別子を求める(割り当て), イベント.束縛の割り当てから設計概念の識別子を求める(割り当て)) else {
                    return 割り当てに無い変数を含む();
                };
                match self.遷移モデル().項から遷移を引き当てる(&遷移の概念) {
                    Some(対象の遷移) => self.発生するかを解く(対象の遷移, &出来事),
                    None => 検証結果::未決定(未決定の理由::対象の概念がグラフに無い(遷移の概念.表記())),
                }
            }
            原子命題::遷移する { 前状態, 入力, 後状態 } => {
                let (Some(前), Some(入), Some(後)) = (
                    前状態.束縛の割り当てから設計概念の識別子を求める(割り当て),
                    入力.束縛の割り当てから設計概念の識別子を求める(割り当て),
                    後状態.束縛の割り当てから設計概念の識別子を求める(割り当て),
                ) else {
                    return 割り当てに無い変数を含む();
                };
                match self.割り当てられた遷移(割り当て) {
                    Some(対象の遷移) => self.遷移するかを解く(対象の遷移, &前, &入, &後),
                    None => 検証結果::未決定(未決定の理由::この検証器が扱わない式を含む("遷移する を、割り当てに遷移が1件も無い位置で問うている".to_string())),
                }
            }
            原子命題::到達可能である { 状態 } => match 状態.束縛の割り当てから設計概念の識別子を求める(割り当て) {
                Some(概念) => self.到達可能であるかを解く(&概念),
                None => 割り当てに無い変数を含む(),
            },
            原子命題::設計関係が在る { .. } | 原子命題::マーカーを持つ { .. } | 原子命題::設計関係へ1つも参加していない { .. } => {
                検証結果::未決定(未決定の理由::この検証器が扱わない式を含む("構造の原子命題は遷移モデルでは解けない".to_string()))
            }
        }
    }

    fn 対象集合を列挙する(&self, 対象: &対象集合) -> Result<列挙した対象, 未決定の理由> {
        match 対象 {
            対象集合::到達可能な状態 => self.上限で切った列挙を組む("到達可能な状態", self.遷移モデル().到達可能な状態一覧を組む().到達順の一覧().to_vec()),
            対象集合::到達可能な遷移 => self.上限で切った列挙を組む("到達可能な遷移", self.遷移モデル().到達可能な遷移一覧().iter().map(|遷移| 遷移.識別子().設計概念の識別子として表す()).collect()),
            対象集合::全ての設計概念 | 対象集合::種類で絞った設計概念(_) | 対象集合::マーカーを持つ設計概念(_) | 対象集合::全ての設計関係の主語(_) => {
                Err(未決定の理由::この検証器が扱わない式を含む("設計関係グラフの対象集合は遷移モデルでは列挙できない".to_string()))
            }
        }
    }
}

impl 命題の検証器 for 有限全数の検証器 {
    fn 検証する(&self, 命題: &命題) -> 検証結果 {
        結合を解く工程::生成する(self).命題を解く(命題)
    }
}

impl 有限全数の検証器 {
    /// 列挙した並びを上限で切り、この検証器が保持している網羅性を名乗る列挙を組む。
    /// 上限を超えたら未決定で答え、切り詰めた一覧を返さない。
    fn 上限で切った列挙を組む(&self, 呼び名: &str, 識別子一覧: Vec<設計概念の識別子>) -> Result<列挙した対象, 未決定の理由> {
        if 識別子一覧.len() > 列挙してよい対象の上限 {
            return Err(未決定の理由::有限に列挙できない(format!("{}が{}件あり、列挙の上限{}件を超える", 呼び名, 識別子一覧.len(), 列挙してよい対象の上限)));
        }
        Ok(列挙した対象 {
            呼び名: 呼び名.to_string(),
            識別子一覧,
            網羅性: self.網羅性().clone(),
        })
    }
}

/// 束縛変数が割り当てに無いときの結末。原子を解く手前で止まったことを、偽と区別して返す。
fn 割り当てに無い変数を含む() -> 検証結果 {
    検証結果::未決定(未決定の理由::この検証器が扱わない式を含む("割り当てに無い束縛変数を含む原子命題である".to_string()))
}
