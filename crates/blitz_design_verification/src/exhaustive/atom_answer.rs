//! 振る舞いの原子命題1つを遷移モデルへ問うて3値で答える工程。
//!
//! 親のファイルから分けるのは、親が担当するのは遷移モデルと網羅性の保持であり、こちらが担当するのは
//! 原子命題1つを名前の付いた問いへ落として証拠・反例・未決定を組むことだからである(CLAUDE.md「切り出しの根拠義務」の5号)。
//! 触れるのは保持している遷移モデルと網羅性の2つだけであり、命題の木も結合の規則も読まない。
//!
//! **`到達可能である` は存在の主張である。** 探索した集合にその状態が在れば網羅していなくても証明済みでよく、
//! 無ければ網羅しているときだけ反証済みで答える。理由は親のファイルの冒頭に書いた。

use super::有限全数の検証器;
use crate::transition_model::遷移;
use crate::{反例, 未決定の理由, 検証の方式, 検証結果, 設計概念の識別子, 証拠};

impl 有限全数の検証器 {
    /// その遷移がその出来事を生成したか。1件の遷移についての問いであるため、網羅性は答えに効かない。
    pub(super) fn 発生するかを解く(&self, 対象の遷移: &遷移, 出来事: &設計概念の識別子) -> 検証結果 {
        if 対象の遷移.その出来事を生成したか(出来事) {
            return 検証結果::証明済み(証拠 {
                方式: 検証の方式::有限全数,
                見た対象の件数: 対象の遷移.生成した出来事一覧().len(),
                説明: format!("遷移 {} が生成した出来事に {} が在る", 対象の遷移.識別子().表記(), 出来事.表記()),
            });
        }
        検証結果::反証済み(反例 {
            方式: 検証の方式::有限全数,
            説明: format!("遷移 {} は {} を生成していない", 対象の遷移.識別子().表記(), 出来事.表記()),
            再現の材料: vec![
                ("前状態".to_string(), 対象の遷移.前状態().表記()),
                ("入力".to_string(), 対象の遷移.入力().表記()),
                ("適用した規則".to_string(), 対象の遷移.適用した規則().表記()),
                ("得られた出来事".to_string(), 得られた出来事の表記(対象の遷移)),
                ("期待した出来事".to_string(), 出来事.表記()),
            ],
        })
    }

    /// その遷移が、その前状態からその入力でその後状態へ移るか。1件の遷移についての問いであるため、網羅性は答えに効かない。
    pub(super) fn 遷移するかを解く(&self, 対象の遷移: &遷移, 前状態: &設計概念の識別子, 入力: &設計概念の識別子, 後状態: &設計概念の識別子) -> 検証結果 {
        let 一致するか = 対象の遷移.前状態() == 前状態 && 対象の遷移.入力() == 入力 && 対象の遷移.後状態() == 後状態;
        if 一致するか {
            return 検証結果::証明済み(証拠 {
                方式: 検証の方式::有限全数,
                見た対象の件数: 1,
                説明: format!("遷移 {} は前状態と入力と後状態の3つが一致する", 対象の遷移.識別子().表記()),
            });
        }
        検証結果::反証済み(反例 {
            方式: 検証の方式::有限全数,
            説明: format!("遷移 {} は前状態と入力と後状態の3つが一致しない", 対象の遷移.識別子().表記()),
            再現の材料: vec![
                ("前状態".to_string(), 対象の遷移.前状態().表記()),
                ("入力".to_string(), 対象の遷移.入力().表記()),
                ("後状態".to_string(), 対象の遷移.後状態().表記()),
                ("問うた前状態".to_string(), 前状態.表記()),
                ("問うた入力".to_string(), 入力.表記()),
                ("問うた後状態".to_string(), 後状態.表記()),
            ],
        })
    }

    /// その状態へ初期状態から到達できるか。探索した集合に在れば証明済み、無ければ網羅性で反証済みと未決定を分ける。
    pub(super) fn 到達可能であるかを解く(&self, 状態: &設計概念の識別子) -> 検証結果 {
        let 到達可能な状態一覧 = self.遷移モデル().到達可能な状態一覧を組む();
        if 到達可能な状態一覧.含むか(状態) {
            return 検証結果::証明済み(証拠 {
                方式: 検証の方式::有限全数,
                見た対象の件数: 到達可能な状態一覧.件数(),
                説明: format!("到達可能な状態を{}件探索し、{} へ到達する経路が在った", 到達可能な状態一覧.件数(), 状態.表記()),
            });
        }
        if !self.網羅性().全件を数え上げたか() {
            return 検証結果::未決定(未決定の理由::探索の範囲では反例が無い {
                探索した件数: 到達可能な状態一覧.件数(),
                探索の範囲の説明: format!("{} へ到達する経路を探索の範囲では見つけられなかった。{}", 状態.表記(), self.網羅性().表記()),
            });
        }
        検証結果::反証済み(反例 {
            方式: 検証の方式::有限全数,
            説明: format!("{} へ初期状態から到達できない", 状態.表記()),
            再現の材料: vec![("到達できない状態".to_string(), 状態.表記()), ("到達可能な状態の件数".to_string(), 到達可能な状態一覧.件数().to_string())],
        })
    }
}

/// 反例へ書く、その遷移が実際に生成した出来事の並び。1件も無いときも空文字にせず、そう分かる語を書く。
fn 得られた出来事の表記(対象の遷移: &遷移) -> String {
    if 対象の遷移.生成した出来事一覧().is_empty() {
        return "1件も生成していない".to_string();
    }
    対象の遷移.生成した出来事一覧().iter().map(設計概念の識別子::表記).collect::<Vec<String>>().join(", ")
}
