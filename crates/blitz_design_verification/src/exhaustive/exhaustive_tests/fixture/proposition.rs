//! 代表ケースの命題の組み立て。正の命題(条件を満たす遷移では専用の事象が発生する)を組む工程を持つ。
//!
//! 命題の形をこの1箇所へ閉じるのは、遷移を量化する全称と、遷移を指す束縛変数と、その変数を使う原子が
//! 同じ変数を指していなければ命題が意味を持たないためである。
//! 否定の命題はこの工程が組まない。否定は排他の推論規則が正の命題から導くものであり、書き下すと導出になっていないことを隠す。

use crate::設計概念への参照;
use crate::{原子命題, 命題, 対象集合, 束縛変数, 非空の命題一覧, 項};

/// 正の命題の材料。5つがどれも設計概念への参照であり、引数として並べると取り違えても型が通るため名前付きの組にする。
pub struct 専用の事象が起きる命題の材料 {
    pub 前状態: 設計概念への参照,
    pub 入力: 設計概念への参照,
    pub 後状態: 設計概念への参照,
    pub 勝利のたびに成立する事象: 設計概念への参照,
    pub 専用の事象: 設計概念への参照,
}

impl 専用の事象が起きる命題の材料 {
    /// 「到達可能な遷移のうち、前状態と入力と後状態がこの組であり、勝利のたびの事象を生成したものは、専用の事象も生成する」を組む。
    /// 前件を連言にするのは、遷移する の3つ組だけでは量化した遷移そのものを名指していないためである。
    /// 発生する の原子が束縛変数を取り、この遷移について問うていることを命題の形の上で示す。
    pub fn 正の命題を組む(&self) -> 命題 {
        let 量化した遷移 = 束縛変数::生成する("遷移");
        let 前件 = 命題::連言(非空の命題一覧::先頭と残りから生成する(
            命題::原子から組む(原子命題::遷移する {
                前状態: 項::名指した概念(self.前状態.clone()),
                入力: 項::名指した概念(self.入力.clone()),
                後状態: 項::名指した概念(self.後状態.clone()),
            }),
            vec![命題::原子(原子命題::発生する {
                遷移: 項::束縛変数(量化した遷移.clone()),
                イベント: 項::名指した概念(self.勝利のたびに成立する事象.clone()),
            })],
        ));
        let 後件 = 命題::原子(原子命題::発生する {
            遷移: 項::束縛変数(量化した遷移.clone()),
            イベント: 項::名指した概念(self.専用の事象.clone()),
        });
        命題::全称 {
            束縛: 量化した遷移,
            対象集合: 対象集合::到達可能な遷移,
            本体: Box::new(命題::含意 {
                前件: Box::new(前件), 後件: Box::new(後件)
            }),
        }
    }
}
