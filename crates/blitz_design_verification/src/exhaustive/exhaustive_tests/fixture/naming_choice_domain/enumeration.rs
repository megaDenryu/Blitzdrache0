//! 名指しを選ぶ領域が、有限に数え上げられる領域として答える実装。
//!
//! 親のファイルから分けるのは、親が持つのが領域の型と選び方の語彙であり、こちらが持つのが
//! 検証の語彙(数え上げ・遷移の帰結)との対応だけであるためである(CLAUDE.md「切り出しの根拠義務」の1号)。
//!
//! 状態の同一性は地点そのものであり、この領域は同一性を1度も畳まない。畳みを選べるのは名指しの側だけである。

use super::{初期状態の数え上げ方, 名指しを選ぶ領域, 地点, 地点の出来事, 地点の名前の空間, 地点の操作};
use crate::{数え上げ, 有限に数え上げられる領域, 設計概念への参照, 遷移の帰結};

// 初期状態を標本で答えるときに名乗る、どの量が連続であるかの説明。
const 初期状態の連続量の説明: &str = "初期の地点は連続量から選んだ代表であり、標本は甲の地点1件に限る";

impl 有限に数え上げられる領域 for 名指しを選ぶ領域 {
    type 状態 = 地点;
    type コマンド = 地点の操作;
    type 出来事 = 地点の出来事;
    type 状態の同一性 = 地点;

    fn 初期状態を数え上げる(&self) -> 数え上げ<地点> {
        let 初期状態一覧 = vec![地点::甲];
        match self.初期状態の数え上げ方() {
            初期状態の数え上げ方::全件で答える => 数え上げ::全件(初期状態一覧),
            初期状態の数え上げ方::連続量を含む標本で答える => 数え上げ::連続量を含む標本 {
                標本: 初期状態一覧,
                連続量の説明: 初期状態の連続量の説明.to_string(),
            },
        }
    }

    fn 状態で試すコマンドを数え上げる(&self, _状態: &地点) -> 数え上げ<地点の操作> {
        数え上げ::全件(vec![地点の操作::甲へ動く, 地点の操作::乙へ動く])
    }

    fn 一回遷移する(&self, _状態: &地点, コマンド: &地点の操作) -> 遷移の帰結<地点, 地点の出来事> {
        match コマンド {
            地点の操作::甲へ動く => 遷移の帰結::成功 {
                次の状態: 地点::甲,
                出来事一覧: vec![地点の出来事::甲へ動いた],
            },
            地点の操作::乙へ動く => 遷移の帰結::成功 {
                次の状態: 地点::乙,
                出来事一覧: vec![地点の出来事::乙へ動いた],
            },
        }
    }

    fn 状態の同一性を答える(&self, 状態: &地点) -> 地点 {
        *状態
    }

    fn 状態を名指す(&self, 状態: &地点) -> 設計概念への参照 {
        self.状態の名指しを組む(状態)
    }

    fn コマンドを名指す(&self, コマンド: &地点の操作) -> 設計概念への参照 {
        self.コマンドの名指しを組む(コマンド)
    }

    fn 出来事を名指す(&self, 出来事: &地点の出来事) -> 設計概念への参照 {
        self.出来事の名指しを組む(出来事)
    }

    fn 規則を名指す(&self) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(地点の名前の空間, "地点を行き来する規則")
    }
}
