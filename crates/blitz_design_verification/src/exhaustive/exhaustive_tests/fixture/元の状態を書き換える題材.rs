//! 失敗のとき、遷移失敗結果の元の状態へ受け取った状態と異なる値を入れて返す、遷移関数の契約を破った領域のfixture。
//! 目盛りを進める領域を包み、失敗の帰結の元の状態だけを最初の初期状態(第0目盛り)へ差し替える。成功の帰結と数え上げと名指しは包んだ領域へそのまま任せる。
//! 探索がこの食い違いを検出し、遷移モデルを返さずに報告することを試験が確かめるために置く。
//!
//! **この領域は検証器自身の単体試験のfixtureであり、実ゲームの仕様の代表ケースでも受理の根拠でもない**(Issue #174 のオーナー裁定)。

use super::countable_domain::目盛りを進める領域;
use crate::{数え上げ, 有限に数え上げられる領域, 設計概念への参照, 遷移の帰結};

/// 失敗の帰結の元の状態を最初の初期状態へ差し替える領域。
pub struct 元の状態を書き換える領域 {
    包む領域: 目盛りを進める領域,
}

impl 元の状態を書き換える領域 {
    /// 上限の目盛りから、包む目盛りを進める領域を組む。
    pub fn 生成する(上限の目盛り: u8) -> Self {
        Self {
            包む領域: 目盛りを進める領域::生成する(上限の目盛り),
        }
    }
}

impl 有限に数え上げられる領域 for 元の状態を書き換える領域 {
    type 状態 = <目盛りを進める領域 as 有限に数え上げられる領域>::状態;
    type コマンド = <目盛りを進める領域 as 有限に数え上げられる領域>::コマンド;
    type 出来事 = <目盛りを進める領域 as 有限に数え上げられる領域>::出来事;
    type 状態の同一性 = <目盛りを進める領域 as 有限に数え上げられる領域>::状態の同一性;

    fn 初期状態を数え上げる(&self) -> 数え上げ<Self::状態> {
        self.包む領域.初期状態を数え上げる()
    }

    fn 状態で試すコマンドを数え上げる(&self, 状態: &Self::状態) -> 数え上げ<Self::コマンド> {
        self.包む領域.状態で試すコマンドを数え上げる(状態)
    }

    /// 包んだ領域の失敗の帰結の元の状態を、最初の初期状態へ差し替える。受け取った状態が最初の初期状態なら、差し替えても等しいままである。
    fn 一回遷移する(&self, 状態: &Self::状態, コマンド: &Self::コマンド) -> 遷移の帰結<Self::状態, Self::出来事> {
        let 初期状態の数え上げ = self.包む領域.初期状態を数え上げる();
        match (self.包む領域.一回遷移する(状態, コマンド), 初期状態の数え上げ.試す値一覧().first()) {
            (遷移の帰結::失敗 { 説明, .. }, Some(最初の初期状態)) => 遷移の帰結::失敗 {
                元の状態: 最初の初期状態.clone(), 説明
            },
            (帰結, _) => 帰結,
        }
    }

    fn 状態の同一性を答える(&self, 状態: &Self::状態) -> Self::状態の同一性 {
        self.包む領域.状態の同一性を答える(状態)
    }

    fn 状態を名指す(&self, 状態: &Self::状態) -> 設計概念への参照 {
        self.包む領域.状態を名指す(状態)
    }

    fn コマンドを名指す(&self, コマンド: &Self::コマンド) -> 設計概念への参照 {
        self.包む領域.コマンドを名指す(コマンド)
    }

    fn 出来事を名指す(&self, 出来事: &Self::出来事) -> 設計概念への参照 {
        self.包む領域.出来事を名指す(出来事)
    }

    fn 規則を名指す(&self) -> 設計概念への参照 {
        self.包む領域.規則を名指す()
    }
}
