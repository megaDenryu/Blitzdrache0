//! 代表ケースの題材が使う概念の名前。状態・入力・規則・事象の4種それぞれが、自分の設計概念の識別子への写し方を持つ。
//!
//! 名前の表記をこの1箇所へ閉じるのは、遷移モデルを組む工程と命題を組む工程が同じ概念を別の表記で書くと、
//! 検証が黙って空虚に成立するためである(前件の状態の名前が1文字違えば、含意は前件が偽で常に成立する)。
//! ここに在る概念はBlitzdracheのドメインの語彙ではなく、有限全数の検証器の題材である。理由は `super` の冒頭に書いた。

use crate::設計概念の識別子;

/// 題材の概念が属する名前の空間。Rustのソースから抽出した概念と混ざらないように、題材の名前だけをここへ入れる。
const 題材の名前の空間: &str = "対戦進行の題材";

/// 専用の事象が起きる対戦回数。事象の名前がこの数を含むため、数と名前が食い違わないよう定数を1つだけ置く。
pub const 専用の事象が起きる対戦回数: u8 = 5;

/// 対戦相手の名前。状態の名前と命題の前件が同じ相手を指すことを型で保つために包む。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 対戦相手の名前(String);

/// 題材の状態。対戦相手と、いま何回戦であるかの組である。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 対戦進行 {
    対戦相手: 対戦相手の名前,
    対戦回数: u8,
}

/// 題材の入力。1回の対戦に勝ったか負けたかである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 対戦の結果 {
    勝利,
    敗北,
}

/// 題材の規則。遷移の「適用した規則」に入る概念である。題材の規則は1つだけであるため、取りうる値も1つである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 対戦進行の規則;

/// 題材の事象。勝利のときに成立する3つを数え上げる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 対戦進行の事象 {
    対戦回数ごとの勝利の事象,
    第5回戦の勝利専用の事象,
    通常の勝利の事象,
}

impl 対戦相手の名前 {
    pub fn 生成する(表記: &str) -> Self {
        Self(表記.to_string())
    }

    pub fn 表記(&self) -> &str {
        &self.0
    }
}

impl 対戦進行 {
    pub fn 生成する(対戦相手: 対戦相手の名前, 対戦回数: u8) -> Self {
        Self { 対戦相手, 対戦回数 }
    }

    pub fn 対戦相手(&self) -> &対戦相手の名前 {
        &self.対戦相手
    }

    pub fn 対戦回数(&self) -> u8 {
        self.対戦回数
    }

    /// 同じ相手のまま次の対戦回数へ進んだ状態。勝利の遷移の後状態がこれである。
    pub fn 次の対戦回数へ進む(&self) -> Self {
        Self {
            対戦相手: self.対戦相手.clone(),
            対戦回数: self.対戦回数.saturating_add(1),
        }
    }

    pub fn 設計概念の識別子(&self) -> 設計概念の識別子 {
        設計概念の識別子::生成する(題材の名前の空間, &format!("対戦進行({}, 第{}回戦)", self.対戦相手.表記(), self.対戦回数))
    }
}

impl 対戦の結果 {
    /// 取りうる値の全件。遷移モデルの組み立てがこの並びを読む。
    pub const fn 全件() -> [Self; 2] {
        [Self::勝利, Self::敗北]
    }

    pub const fn 語(self) -> &'static str {
        match self {
            Self::勝利 => "勝利",
            Self::敗北 => "敗北",
        }
    }

    pub fn 設計概念の識別子(self) -> 設計概念の識別子 {
        設計概念の識別子::生成する(題材の名前の空間, &format!("対戦の結果({})", self.語()))
    }
}

impl 対戦進行の規則 {
    pub fn 設計概念の識別子(self) -> 設計概念の識別子 {
        設計概念の識別子::生成する(題材の名前の空間, "対戦進行の規則")
    }
}

impl 対戦進行の事象 {
    pub const fn 語(self) -> &'static str {
        match self {
            Self::対戦回数ごとの勝利の事象 => "対戦回数ごとの勝利の事象",
            Self::第5回戦の勝利専用の事象 => "第5回戦の勝利専用の事象",
            Self::通常の勝利の事象 => "通常の勝利の事象",
        }
    }

    pub fn 設計概念の識別子(self) -> 設計概念の識別子 {
        設計概念の識別子::生成する(題材の名前の空間, self.語())
    }
}
