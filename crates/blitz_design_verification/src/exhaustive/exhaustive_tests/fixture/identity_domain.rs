//! 状態の同一性の写し方を選べるfixture。歩数を1つずつ動かすだけの領域であり、取りうるコマンドを全件で数え上げる。
//!
//! **この領域は検証器自身の単体試験のfixtureであり、実ゲームの仕様の代表ケースでも受理の根拠でもない**
//! (Issue #174 のオーナー裁定)。歩数は実在のドメインの量ではない。
//!
//! 名指し方と同一性の写し方を別々に選べるようにしてあるのは、この2つが別の口であることを試験が確かめるためである。
//! 粗く名指す領域でも、同一性が畳まなければ探索は状態を1件も捨てない。同一性が名指しと同じ粗さで畳めば、探索は畳みを検出して
//! 全件を名乗らない。歩数の上限と下限で同じ説明の文で失敗するのは、同じ文面の別の失敗が1つの節点へ畳まれないことを見るためである。

use blitz_design::{Mイベント, Mコマンド, M不変データ, M状態};

use crate::{数え上げ, 有限に数え上げられる領域, 設計概念の識別子, 遷移の帰結};

/// fixtureの名前の空間。Rustのソースから抽出した概念と混ざらないようにこの表記だけをここへ入れる。
const 歩数の名前の空間: &str = "歩数を動かす領域のfixture";

// 上限でも下限でも同じ文で失敗する。同じ文面の別の失敗が同じ節点へ畳まれないことを見るために、意図して同じ文にしてある。
const 動けない説明: &str = "これ以上は動けない";

/// この領域の状態。いま何歩目に居るかである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct 歩数(u8);

/// この領域のコマンド。1歩進むか1歩戻るかである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 歩数の操作 {
    進む,
    戻る,
}

/// この領域の出来事。歩数が1つ動いたことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 歩数の出来事 {
    歩数が1つ動いた,
}

/// 状態の名指し方。人が読む表示の粗さを選ぶ。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 状態の名指し方 {
    /// 歩数をそのまま名前に入れる。異なる歩数が同じ名前を持つことは無い。
    歩数をそのまま名指す,
    /// 歩数の偶奇だけを名前に入れる。歩数0と歩数2が同じ名前を持つ。`blitz_esca` が位置をマスの番号へ丸めるのと同じ粗さである。
    偶奇だけで名指す,
}

/// 状態の同一性の写し方。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 状態の同一性の写し方 {
    /// 歩数をそのまま同一性にする。異なる歩数が同じ同一性へ写ることは無い。
    歩数をそのまま写す,
    /// 歩数の偶奇だけを同一性にする。歩数0と歩数2が同じ同一性へ写り、探索が2件目を捨てる。
    偶奇へ畳む,
}

/// 歩数を0から上限までの間で動かす領域。
pub struct 歩数を動かす領域 {
    上限の歩数: u8,
    名指し方: 状態の名指し方,
    写し方: 状態の同一性の写し方,
}

impl M不変データ for 歩数 {}
impl M状態 for 歩数 {}
impl M不変データ for 歩数の操作 {}
impl Mコマンド for 歩数の操作 {}
impl M不変データ for 歩数の出来事 {}
impl Mイベント for 歩数の出来事 {}

impl 歩数を動かす領域 {
    /// 上限の歩数と名指し方と同一性の写し方から領域を組む。
    pub fn 生成する(上限の歩数: u8, 名指し方: 状態の名指し方, 写し方: 状態の同一性の写し方) -> Self {
        Self { 上限の歩数, 名指し方, 写し方 }
    }
}

impl 有限に数え上げられる領域 for 歩数を動かす領域 {
    type 状態 = 歩数;
    type コマンド = 歩数の操作;
    type 出来事 = 歩数の出来事;
    type 状態の同一性 = u8;

    fn 初期状態一覧(&self) -> Vec<Self::状態> {
        vec![歩数(0)]
    }

    fn 状態で試すコマンドを数え上げる(&self, _状態: &Self::状態) -> 数え上げ<Self::コマンド> {
        数え上げ::全件(vec![歩数の操作::進む, 歩数の操作::戻る])
    }

    fn 一回遷移する(&self, 状態: &Self::状態, コマンド: &Self::コマンド) -> 遷移の帰結<Self::状態, Self::出来事> {
        let 動けた先の歩数 = match コマンド {
            歩数の操作::進む => (状態.0 < self.上限の歩数).then(|| 状態.0.saturating_add(1)),
            歩数の操作::戻る => (状態.0 > 0).then(|| 状態.0.saturating_sub(1)),
        };
        match 動けた先の歩数 {
            Some(次の歩数) => 遷移の帰結::成功 {
                次の状態: 歩数(次の歩数),
                出来事一覧: vec![歩数の出来事::歩数が1つ動いた],
            },
            None => 遷移の帰結::失敗 { 説明: 動けない説明.to_string() },
        }
    }

    fn 状態の同一性を答える(&self, 状態: &Self::状態) -> Self::状態の同一性 {
        match self.写し方 {
            状態の同一性の写し方::歩数をそのまま写す => 状態.0,
            状態の同一性の写し方::偶奇へ畳む => 状態.0 % 2,
        }
    }

    fn 状態を名指す(&self, 状態: &Self::状態) -> 設計概念の識別子 {
        let 表記 = match self.名指し方 {
            状態の名指し方::歩数をそのまま名指す => format!("歩数(第{}歩)", 状態.0),
            状態の名指し方::偶奇だけで名指す => format!("歩数({}歩目)", if 状態.0 % 2 == 0 { "偶数" } else { "奇数" }),
        };
        設計概念の識別子::実行時のドメイン概念として生成する(歩数の名前の空間, &表記)
    }

    fn コマンドを名指す(&self, コマンド: &Self::コマンド) -> 設計概念の識別子 {
        let 語 = match コマンド {
            歩数の操作::進む => "進む",
            歩数の操作::戻る => "戻る",
        };
        設計概念の識別子::実行時のドメイン概念として生成する(歩数の名前の空間, &format!("歩数の操作({語})"))
    }

    fn 出来事を名指す(&self, _出来事: &Self::出来事) -> 設計概念の識別子 {
        設計概念の識別子::実行時のドメイン概念として生成する(歩数の名前の空間, "歩数が1つ動いた")
    }

    fn 規則を名指す(&self) -> 設計概念の識別子 {
        設計概念の識別子::実行時のドメイン概念として生成する(歩数の名前の空間, "歩数を動かす規則")
    }
}
