//! `有限に数え上げられる領域` を実装するfixture。目盛りを1つずつ進めるだけの領域であり、
//! 探索が実物の遷移の口を呼んで遷移モデルを組めることと、数え上げが標本に限ると名乗ったときに
//! 網羅性がそれを引き継ぐことを試験が確かめるために置く。
//!
//! **この領域は検証器自身の単体試験のfixtureであり、実ゲームの仕様の代表ケースでも受理の根拠でもない**
//! (Issue #174 のオーナー裁定)。目盛りは実在のドメインの量ではない。
//!
//! 数え上げを `連続量を含む標本` で答えるのは、実ゲームの領域(歩行方向のように連続量を引数に取るコマンドを持つ領域)が
//! 標本しか並べられないことを、この小さな領域で写すためである。

use blitz_design::{Mイベント, Mコマンド, M不変データ, M状態};

use crate::{数え上げ, 有限に数え上げられる領域, 設計概念への参照, 遷移の帰結};

/// fixtureの名前の空間。Rustのソースから抽出した概念と混ざらないようにこの表記だけをここへ入れる。
const 目盛りの名前の空間: &str = "目盛りを進める領域のfixture";

/// この領域の状態。いま何番目の目盛りに居るかである。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct 目盛りの位置 {
    目盛り: u8,
}

/// この領域のコマンド。進めるか止まるかである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 目盛りの操作 {
    進める,
    止まる,
}

/// この領域の出来事。目盛りが1つ進んだことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 目盛りの出来事 {
    目盛りが1つ進んだ,
}

/// 目盛りを上限まで進める領域。上限の目盛りを保持し、そこから先へは進めない。
pub struct 目盛りを進める領域 {
    上限の目盛り: u8,
}

impl M不変データ for 目盛りの位置 {}
impl M状態 for 目盛りの位置 {}
impl M不変データ for 目盛りの操作 {}
impl Mコマンド for 目盛りの操作 {}
impl M不変データ for 目盛りの出来事 {}
impl Mイベント for 目盛りの出来事 {}

impl 目盛りを進める領域 {
    /// 上限の目盛りから領域を組む。
    pub fn 生成する(上限の目盛り: u8) -> Self {
        Self { 上限の目盛り }
    }
}

impl 有限に数え上げられる領域 for 目盛りを進める領域 {
    type 状態 = 目盛りの位置;
    type コマンド = 目盛りの操作;
    type 出来事 = 目盛りの出来事;
    type 状態の同一性 = 目盛りの位置;

    fn 初期状態一覧(&self) -> Vec<Self::状態> {
        vec![目盛りの位置 { 目盛り: 0 }]
    }

    fn 状態で試すコマンドを数え上げる(&self, _状態: &Self::状態) -> 数え上げ<Self::コマンド> {
        数え上げ::連続量を含む標本 {
            標本: vec![目盛りの操作::進める, 目盛りの操作::止まる],
            連続量の説明: "進める量が連続量であると仮に名乗らせたfixtureである".to_string(),
        }
    }

    fn 一回遷移する(&self, 状態: &Self::状態, コマンド: &Self::コマンド) -> 遷移の帰結<Self::状態, Self::出来事> {
        match コマンド {
            目盛りの操作::止まる => 遷移の帰結::成功 {
                次の状態: 状態.clone(),
                出来事一覧: Vec::new(),
            },
            目盛りの操作::進める if 状態.目盛り < self.上限の目盛り => 遷移の帰結::成功 {
                次の状態: 目盛りの位置 { 目盛り: 状態.目盛り.saturating_add(1) },
                出来事一覧: vec![目盛りの出来事::目盛りが1つ進んだ],
            },
            目盛りの操作::進める => 遷移の帰結::失敗 {
                説明: format!("目盛り{}は上限{}であり、これ以上進めない", 状態.目盛り, self.上限の目盛り),
            },
        }
    }

    /// 状態そのものを同一性にする。目盛りは整数であり、異なる目盛りが同じ同一性へ写ることはない。
    fn 状態の同一性を答える(&self, 状態: &Self::状態) -> Self::状態の同一性 {
        状態.clone()
    }

    fn 状態を名指す(&self, 状態: &Self::状態) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(目盛りの名前の空間, &format!("目盛りの位置(第{}目盛り)", 状態.目盛り))
    }

    fn コマンドを名指す(&self, コマンド: &Self::コマンド) -> 設計概念への参照 {
        let 語 = match コマンド {
            目盛りの操作::進める => "進める",
            目盛りの操作::止まる => "止まる",
        };
        設計概念への参照::実行時のドメイン概念として生成する(目盛りの名前の空間, &format!("目盛りの操作({語})"))
    }

    fn 出来事を名指す(&self, _出来事: &Self::出来事) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(目盛りの名前の空間, "目盛りが1つ進んだ")
    }

    fn 規則を名指す(&self) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(目盛りの名前の空間, "目盛りを進める規則")
    }
}
