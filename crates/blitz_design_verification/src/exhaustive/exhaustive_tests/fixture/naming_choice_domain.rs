//! 名指しの選び方と初期状態の数え上げ方を選べるfixture。2つの地点を行き来するだけの領域である。
//!
//! **この領域は検証器自身の単体試験のfixtureであり、実ゲームの仕様の代表ケースでも受理の根拠でもない**
//! (Issue #174 のオーナー裁定)。地点も甲乙も実在のドメインの量ではない。
//!
//! 状態の同一性は常に地点そのものでありまとめない。まとめるかどうかを名指しの側だけで選べるようにしてあるのは、
//! 名指しの重複のまとめが同一性の重複のまとめとは別の欠陥であることを試験が見るためである。
//! 繋いだ表記が紛れる名前を選べるのは、遷移の識別子が前状態と入力を1本の文字列へ連結しないことを見るためである
//! 参照: `crates/blitz_design_verification/src/transition_model/transition_identifier.rs`。
//!
//! 名指しの実装は子モジュールに置く(CLAUDE.md「切り出しの根拠義務」の5号の、名前の付く工程の分離)。

mod enumeration;
mod naming;

use blitz_design::{Mイベント, Mコマンド, M不変データ, M状態};

/// fixtureの名前の空間。Rustのソースから抽出した概念と混ざらないようにこの表記だけをここへ入れる。
pub(super) const 地点の名前の空間: &str = "名指しを選ぶ領域のfixture";

/// この領域の状態。甲の地点と乙の地点の2つしかない。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum 地点 {
    甲,
    乙,
}

/// この領域のコマンド。どちらの地点へ動くかである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 地点の操作 {
    甲へ動く,
    乙へ動く,
}

/// この領域の出来事。どちらの地点へ動いたかである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 地点の出来事 {
    甲へ動いた,
    乙へ動いた,
}

/// 名指しの選び方。どこでまとめるか、あるいは繋いだ表記が紛れる名前にするかを選ぶ。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 名指しの選び方 {
    /// 状態もコマンドも出来事も、互いに等しくない値へ別の名前を与える。
    どれも同じ名前にまとめない,
    /// 2つのコマンドへ同じ名前を与える。
    コマンドを同じ名前にまとめる,
    /// 2つの出来事へ同じ名前を与える。
    出来事を同じ名前にまとめる,
    /// どの名前も互いに別でありながら、前状態と入力の表記を繋ぐと別の組と同じ1行になる名前にする。
    繋いだ表記が紛れる名前にする,
}

/// 初期状態の数え上げ方。全件で答えるか、連続量を含む標本で答えるかである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 初期状態の数え上げ方 {
    /// 初期状態を全件並べたと名乗る。
    全件で答える,
    /// 初期状態は代表の標本に限ると名乗る。
    連続量を含む標本で答える,
}

/// 領域の組み立ての入力。同型の列挙を引数として並べると取り違えても型が通るため名前付きの組にする。
pub struct 名指しを選ぶ領域の構成 {
    /// 名指しをどう選ぶか。
    pub 名指しの選び方: 名指しの選び方,
    /// 初期状態をどう数え上げるか。
    pub 初期状態の数え上げ方: 初期状態の数え上げ方,
}

/// 2つの地点を行き来する領域。名指しの選び方と初期状態の数え上げ方を構成で受け取る。
pub struct 名指しを選ぶ領域 {
    構成: 名指しを選ぶ領域の構成,
}

impl M不変データ for 地点 {}
impl M状態 for 地点 {}
impl M不変データ for 地点の操作 {}
impl Mコマンド for 地点の操作 {}
impl M不変データ for 地点の出来事 {}
impl Mイベント for 地点の出来事 {}

impl 名指しを選ぶ領域 {
    /// 構成から領域を組む。
    pub fn 生成する(構成: 名指しを選ぶ領域の構成) -> Self {
        Self { 構成 }
    }

    /// この領域が選んだ名指しの選び方。
    pub(super) const fn 名指しの選び方(&self) -> 名指しの選び方 {
        self.構成.名指しの選び方
    }

    /// この領域が選んだ初期状態の数え上げ方。
    pub(super) const fn 初期状態の数え上げ方(&self) -> 初期状態の数え上げ方 {
        self.構成.初期状態の数え上げ方
    }
}
