#[test]
fn 存在の証人が0件のとき網羅していれば反証済みで網羅していなければ未決定になる() {
    let 題材 = 対戦進行の題材::生成する();
    let 命題 = その出来事が発生する遷移が在る存在(一度も成立しない出来事());
    let 全件の結末 = 有限全数の検証器::生成する(網羅性を付けた探索の結末(&題材, 数え上げの網羅性::全件を数え上げた)).検証する(&命題);
    assert!(全件の結末.反証済みか(), "全件を数え上げた網羅性では反証済みでなければならない: {}", 全件の結末.表記());
    let 標本の結末 = 有限全数の検証器::生成する(網羅性を付けた探索の結末(&題材, 連続量の標本に限る())).検証する(&命題);
    assert!(
        matches!(標本の結末, 検証結果::未決定(未決定の理由::探索の範囲では反例が無い { .. })),
        "見ていない範囲に証人が居るかもしれないため未決定でなければならない: {}",
        標本の結末.表記()
    );
}
