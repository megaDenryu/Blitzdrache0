//! 数え上げの網羅性が答えに効くかどうかが命題の形によって非対称であることを固定する試験。
//!
//! **反例と存在の証人は「見た範囲」から得られるが、全称の成立と存在の不在は「見ていない範囲」に依る。**
//! 4つの試験はこの1文を4行の表として固定する。全称の全件成立と存在の証人0件だけが網羅性で答えを変え、
//! 全称の反例と存在の証人は網羅性に関わらず同じ答えになる。
//! 網羅性だけが違う2つの探索の結末を同じモデルから組むため、答えの違いがモデルの違いから来ることは無い。

#![allow(clippy::unwrap_used)]

use super::fixture::{対戦進行の事象, 対戦進行の題材};
use crate::{原子命題, 命題, 命題の検証器, 対象集合, 探索の結末, 数え上げの網羅性, 有限全数の検証器, 未決定の理由, 束縛変数, 検証結果, 設計概念の識別子, 項};

/// 題材のモデルへ、名乗らせたい網羅性を付けた探索の結末。
fn 網羅性を付けた探索の結末(題材: &対戦進行の題材, 網羅性: 数え上げの網羅性) -> 探索の結末 {
    探索の結末 {
        モデル: 題材.遷移モデルを組む(), 網羅性
    }
}

/// 標本に限ると名乗らせる網羅性。実ゲームの連続量を含む領域の立場を、この題材へ仮に負わせる。
fn 連続量の標本に限る() -> 数え上げの網羅性 {
    数え上げの網羅性::連続量の標本に限る {
        説明一覧: vec!["この題材へ仮に連続量を含む領域の立場を負わせた".to_string()],
    }
}

/// どの遷移も生成しない出来事。存在の証人が0件になる命題を組むために置く。
fn 一度も成立しない出来事() -> 設計概念の識別子 {
    設計概念の識別子::実行時のドメイン概念として生成する("対戦進行の題材", "一度も成立しない事象")
}

/// 到達可能な遷移について、その出来事が発生することを問う全称。
fn その出来事が全ての遷移で発生する全称(出来事: 設計概念の識別子) -> 命題 {
    let 束縛 = 束縛変数::生成する("遷移");
    命題::全称を組む(束縛.clone(), 対象集合::到達可能な遷移, 発生するの原子(&束縛, 出来事))
}

/// 到達可能な遷移について、その出来事が発生するものが在ることを問う存在。
fn その出来事が発生する遷移が在る存在(出来事: 設計概念の識別子) -> 命題 {
    let 束縛 = 束縛変数::生成する("遷移");
    命題::存在を組む(束縛.clone(), 対象集合::到達可能な遷移, 発生するの原子(&束縛, 出来事))
}

fn 発生するの原子(束縛: &束縛変数, 出来事: 設計概念の識別子) -> 命題 {
    命題::原子から組む(原子命題::発生する {
        遷移: 項::束縛変数(束縛.clone()),
        イベント: 項::名指した概念(出来事),
    })
}

#[test]
fn 全称が全件で成立するとき網羅していれば証明済みで網羅していなければ未決定になる() {
    let 題材 = 対戦進行の題材::生成する();
    let 命題 = 題材.専用の事象が起きる命題を組む();
    let 全件の結末 = 有限全数の検証器::生成する(網羅性を付けた探索の結末(&題材, 数え上げの網羅性::全件を数え上げた)).検証する(&命題);
    assert!(全件の結末.証明済みか(), "全件を数え上げた網羅性では証明済みでなければならない: {}", 全件の結末.表記());
    let 標本の結末 = 有限全数の検証器::生成する(網羅性を付けた探索の結末(&題材, 連続量の標本に限る())).検証する(&命題);
    match &標本の結末 {
        検証結果::未決定(未決定の理由::探索の範囲では反例が無い { 探索した件数, 探索の範囲の説明 }) => {
            assert!(*探索した件数 > 0, "探索した件数を0件と答えてはならない");
            assert!(探索の範囲の説明.contains("連続量"), "未決定の理由の文へ連続量の説明が入っていない: {探索の範囲の説明}");
        }
        それ以外 => panic!("標本に限る網羅性で全称を証明済みと答えてはならない: {}", それ以外.表記()),
    }
}

#[test]
fn 全称の反例は網羅していなくても反証済みになる() {
    let 題材 = 対戦進行の題材::生成する();
    let 命題 = その出来事が全ての遷移で発生する全称(一度も成立しない出来事());
    let 結末 = 有限全数の検証器::生成する(網羅性を付けた探索の結末(&題材, 連続量の標本に限る())).検証する(&命題);
    assert!(結末.反証済みか(), "標本の中の反例は本物の反例であるため反証済みでなければならない: {}", 結末.表記());
}

#[test]
