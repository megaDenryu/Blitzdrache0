    let 題材 = 対戦進行の題材::生成する();
    let 命題 = その出来事が発生する遷移が在る存在(対戦進行の事象::対戦回数ごとの勝利の事象.設計概念の識別子());
    let 結末 = 有限全数の検証器::生成する(網羅性を付けた探索の結末(&題材, 連続量の標本に限る())).検証する(&命題);
