//! 検証器自身の単体試験のfixture。有限全数の検証器が振る舞いの命題を解けることを示すための、有限の対戦進行を組む。
//!
//! **この題材は検証器自身の単体試験のfixtureであり、実ゲームの仕様の代表ケースでも受理の根拠でもない**
//! (Issue #174 のオーナー裁定)。公開の口から外してあり、`cargo xtask design-verify` はこの題材を1度も呼ばない。
//! ここに在る対戦進行・対戦の結果・対戦進行の規則・3つの事象はBlitzdracheのドメインの語彙ではないため、
//! `_doc/計画/ユビキタス言語.md` にも `_doc/計画/裁定待ちユビキタス言語.md` にも登録しない。
//!
//! 実ゲームの振る舞いの命題は、ドメインのクレートの試験が `有限に数え上げられる領域` を実装し、実物の遷移関数を呼んで検証する。

mod concepts;
mod countable_domain;
mod identity_domain;
mod proposition;

pub use concepts::{対戦の結果, 対戦相手の名前, 対戦進行, 対戦進行の事象, 対戦進行の規則, 専用の事象が起きる対戦回数};
pub use countable_domain::目盛りを進める領域;
pub use identity_domain::{歩数を動かす領域, 状態の同一性の写し方, 状態の名指し方};

use crate::transition_model::{遷移, 遷移の材料, 遷移の識別子, 遷移モデル};
use crate::設計概念の識別子;
use crate::{命題, 排他の推論規則};
use proposition::専用の事象が起きる命題の材料;

/// 対戦進行の題材。対戦相手2人と、専用の事象が起きる対戦回数までの有限の進行を持つ。
pub struct 対戦進行の題材 {
    名指した対戦相手: 対戦相手の名前,
    もう一方の対戦相手: 対戦相手の名前,
}

impl Default for 対戦進行の題材 {
    fn default() -> Self {
        Self::生成する()
    }
}

impl 対戦進行の題材 {
    /// 題材を組む。対戦相手の名前は、専用の事象が起きる側と起きない側を名前そのもので区別する。
    pub fn 生成する() -> Self {
        Self {
            名指した対戦相手: 対戦相手の名前::生成する("専用の事象が起きる対戦相手"),
            もう一方の対戦相手: 対戦相手の名前::生成する("専用の事象が起きない対戦相手"),
        }
    }

    /// 対戦相手2人 × 対戦回数1から専用の事象が起きる対戦回数まで × 結果2通りの有限の遷移モデルを組む。
    pub fn 遷移モデルを組む(&self) -> 遷移モデル {
        let 対戦相手一覧 = [self.名指した対戦相手.clone(), self.もう一方の対戦相手.clone()];
        let 初期状態一覧 = 対戦相手一覧.iter().map(|相手| 対戦進行::生成する(相手.clone(), 1).設計概念の識別子()).collect();
        let mut 遷移一覧 = Vec::new();
        for 相手 in &対戦相手一覧 {
            for 対戦回数 in 1..=専用の事象が起きる対戦回数 {
                let 前状態 = 対戦進行::生成する(相手.clone(), 対戦回数);
                for 結果 in 対戦の結果::全件() {
                    遷移一覧.push(self.勝敗ごとの遷移を組む(&前状態, 結果));
                }
            }
        }
        遷移モデル::生成する(初期状態一覧, 遷移一覧)
    }

    /// 1つの前状態と1つの結果から遷移1件を組む。敗北は対戦回数を進めず出来事を1件も生成しない(同じ回戦をやり直す)。
    fn 勝敗ごとの遷移を組む(&self, 前状態: &対戦進行, 結果: 対戦の結果) -> 遷移 {
        let 材料 = 遷移の材料 {
            識別子: 遷移の識別子::生成する(&format!("{}の{}", 前状態.設計概念の識別子().表記(), 結果.語())),
            前状態: 前状態.設計概念の識別子(),
            入力: 結果.設計概念の識別子(),
            適用した規則: 対戦進行の規則.設計概念の識別子(),
        };
        match 結果 {
            対戦の結果::敗北 => 遷移::成功として生成する(材料, 前状態.設計概念の識別子(), Vec::new()),
            対戦の結果::勝利 => {
                let 後状態 = 前状態.次の対戦回数へ進む().設計概念の識別子();
                遷移::成功として生成する(材料, 後状態, self.勝利で成立する出来事一覧(前状態))
            }
        }
    }

    /// 勝利で成立する出来事。対戦回数ごとの勝利の事象は必ず成立し、名指した対戦相手の最終の対戦回数の勝利だけが
    /// 専用の事象を、それ以外の勝利が通常の勝利の事象を成立させる。
    fn 勝利で成立する出来事一覧(&self, 前状態: &対戦進行) -> Vec<設計概念の識別子> {
        let 専用の事象が起きるか = 前状態.対戦相手() == &self.名指した対戦相手 && 前状態.対戦回数() == 専用の事象が起きる対戦回数;
        let 勝ち方の事象 = if 専用の事象が起きるか {
            対戦進行の事象::第5回戦の勝利専用の事象
        } else {
            対戦進行の事象::通常の勝利の事象
        };
        vec![対戦進行の事象::対戦回数ごとの勝利の事象.設計概念の識別子(), 勝ち方の事象.設計概念の識別子()]
    }

    /// 正の命題。名指した対戦相手の最終の対戦回数の勝利では専用の事象が発生する。
    pub fn 専用の事象が起きる命題を組む(&self) -> 命題 {
        self.正の命題の材料を組む().正の命題を組む()
    }

    /// 排他の推論規則。専用の事象と通常の勝利の事象は同時に成立しない。
    pub fn 排他の推論規則を組む(&self) -> 排他の推論規則 {
        排他の推論規則::生成する(対戦進行の事象::第5回戦の勝利専用の事象.設計概念の識別子(), 対戦進行の事象::通常の勝利の事象.設計概念の識別子())
    }

    /// 正の命題と排他の推論規則から導いた否定の命題。書き下すのではなく導くため、導けない形なら`None`で返る。
    pub fn 通常の勝利の事象が起きない命題を導く(&self) -> Option<命題> {
        self.排他の推論規則を組む().発生の否定へ置き換えた命題を導く(&self.専用の事象が起きる命題を組む())
    }

    fn 正の命題の材料を組む(&self) -> 専用の事象が起きる命題の材料 {
        let 前状態 = 対戦進行::生成する(self.名指した対戦相手.clone(), 専用の事象が起きる対戦回数);
        専用の事象が起きる命題の材料 {
            前状態: 前状態.設計概念の識別子(),
            入力: 対戦の結果::勝利.設計概念の識別子(),
            後状態: 前状態.次の対戦回数へ進む().設計概念の識別子(),
            勝利のたびに成立する事象: 対戦進行の事象::対戦回数ごとの勝利の事象.設計概念の識別子(),
            専用の事象: 対戦進行の事象::第5回戦の勝利専用の事象.設計概念の識別子(),
        }
    }
}
