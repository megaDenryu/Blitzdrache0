#[test]
fn 構造の原子命題を有限全数の検証器へ渡すと未決定になる() {
    let 題材 = 対戦進行の題材::生成する();
    let 概念 = 対戦進行の規則.設計概念への参照();
    let 命題 = 命題::原子から組む(原子命題::設計関係へ1つも参加していない { 概念: 項::名指した概念(概念) });
    let 結末 = 有限全数の検証器::生成する(全件を数え上げた探索の結末(題材.遷移モデルを組む())).検証する(&命題);
    assert!(!結末.証明済みか() && !結末.反証済みか(), "構造の原子命題が未決定にならなかった: {}", 結末.表記());
}

#[test]
fn 失敗した遷移は出来事を1件も生成せず後状態が前状態と同じである() {
    let 前状態 = 対戦進行::生成する(対戦相手の名前::生成する("題材の対戦相手"), 1).設計概念への参照();
    let 材料 = 遷移の材料 {
        識別子: 遷移の識別子::生成する("失敗した遷移"),
        前状態: 前状態.clone(),
        入力: 対戦の結果::敗北.設計概念への参照(),
        適用した規則: 対戦進行の規則.設計概念への参照(),
    };
    let 失敗した遷移 = 遷移::失敗として生成する(材料, 対戦進行の事象::通常の勝利の事象.設計概念への参照());
    assert!(失敗した遷移.生成した出来事一覧().is_empty());
    assert_eq!(失敗した遷移.後状態(), &前状態);
    assert_eq!(専用の事象が起きる対戦回数, 5);
}

/// 壊したモデルを組むための、専用の事象だけを落とした同じ遷移。
fn 専用の事象を落とした遷移(元の遷移: &遷移) -> 遷移 {
    let 材料 = 遷移の材料 {
        識別子: 元の遷移.識別子().clone(),
        前状態: 元の遷移.前状態().clone(),
        入力: 元の遷移.入力().clone(),
        適用した規則: 元の遷移.適用した規則().clone(),
    };
    let 落とす = 対戦進行の事象::第5回戦の勝利専用の事象.設計概念への参照();
    let 残した出来事一覧 = 元の遷移.生成した出来事一覧().iter().filter(|出来事| *出来事 != &落とす).cloned().collect();
    遷移::成功として生成する(材料, 元の遷移.後状態().clone(), 残した出来事一覧)
}
