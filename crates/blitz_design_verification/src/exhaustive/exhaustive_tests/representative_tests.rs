/// 題材のモデルを、全件を数え上げたと名乗る探索の結末へ包む。この題材は取りうる値を全部並べられる。
fn 全件を数え上げた探索の結末(モデル: 遷移モデル) -> 探索の結末 {
    探索の結末 {
        モデル,
        網羅性: 数え上げの網羅性::全件を数え上げた,
    }
}

#[test]
fn 代表ケースの正の命題は証明済みになり証拠の見た対象の件数が列挙した遷移の件数と一致する() {
    let 題材 = 対戦進行の題材::生成する();
    let 遷移モデル = 題材.遷移モデルを組む();
    let 到達可能な遷移の件数 = 遷移モデル.到達可能な遷移一覧().len();
    let 結末 = 有限全数の検証器::生成する(全件を数え上げた探索の結末(遷移モデル)).検証する(&題材.専用の事象が起きる命題を組む());
    match 結末 {
        検証結果::証明済み(証拠) => assert_eq!(証拠.見た対象の件数, 到達可能な遷移の件数),
        それ以外 => panic!("正の命題が証明済みにならなかった: {}", それ以外.表記()),
    }
}

#[test]
fn 排他の推論規則から導いた否定の命題は証明済みになる() {
    let 題材 = 対戦進行の題材::生成する();
    let 検証器 = 有限全数の検証器::生成する(全件を数え上げた探索の結末(題材.遷移モデルを組む()));
    let 否定の命題 = 題材.通常の勝利の事象が起きない命題を導く().unwrap();
    let 結末 = 検証器.検証する(&否定の命題);
    assert!(結末.証明済みか(), "導いた否定の命題が証明済みにならなかった: {}", 結末.表記());
}

#[test]
fn 専用の事象を生成しないよう壊したモデルでは正の命題が反証済みになり反例に再現の材料が入る() {
    let 題材 = 対戦進行の題材::生成する();
    let 壊した遷移一覧 = 題材
        .遷移モデルを組む()
        .遷移一覧()
        .iter()
        .map(|遷移| {
            if 遷移.その出来事を生成したか(&対戦進行の事象::第5回戦の勝利専用の事象.設計概念への参照()) {
                専用の事象を落とした遷移(遷移)
            } else {
                遷移.clone()
            }
        })
        .collect();
    let 壊したモデル = 遷移モデル::生成する(題材.遷移モデルを組む().初期状態一覧().to_vec(), 壊した遷移一覧);
    let 結末 = 有限全数の検証器::生成する(全件を数え上げた探索の結末(壊したモデル)).検証する(&題材.専用の事象が起きる命題を組む());
    match 結末 {
        検証結果::反証済み(反例) => {
            let 材料の名前一覧: Vec<&str> = 反例.再現の材料.iter().map(|(名前, _)| 名前.as_str()).collect();
            for 要る名前 in ["前状態", "入力", "得られた出来事", "期待した出来事"] {
                assert!(材料の名前一覧.contains(&要る名前), "反例の再現の材料に{要る名前}が無い");
            }
        }
        それ以外 => panic!("壊したモデルで正の命題が反証済みにならなかった: {}", それ以外.表記()),
    }
}

#[test]
