//! 領域が答えた同一性と名指しの畳みを探索が検出することを固定する試験。
//!
//! 領域は同一性も名指しも自分で書くため、互いに等しくない2つの値を同じ答えへ写す実装を書ける。
//! 書けること自体は止められないため、探索がその事実を残して全件を名乗らないことをここで固定する。
//! 遷移の識別子が前状態と入力を1本の文字列へ畳まないことと、同じ説明の文で失敗する2件の遷移が別の節点へ写ることも、
//! どちらも名前が紛れるかどうかの話であるためここで見る。

#![allow(clippy::unwrap_used)]

use super::super::fixture::{初期状態の数え上げ方, 名指しの選び方, 名指しを選ぶ領域, 名指しを選ぶ領域の構成, 歩数を動かす領域, 状態の同一性の写し方, 状態の名指し方};
use crate::{探索の上限, 探索の結末, 数え上げの網羅性, 設計概念への参照, 領域から遷移モデルを組む};

#[test]
fn 粗く名指す領域は状態を1件も捨てないが網羅性は名指しの畳みを名乗る() {
    // 探索そのものは同一性で辿るため、名前が2種類しか無くても3件の状態を辿り切る。
    // ただしモデルの上では別の状態が1件の節点へ重なり、命題の層がその2つを区別できないため、全件は名乗れない。
    let 領域 = 歩数を動かす領域::生成する(2, 状態の名指し方::偶奇だけで名指す, 状態の同一性の写し方::歩数をそのまま写す);
    let 結末 = 領域から遷移モデルを組む(&領域, 探索の上限::default());
    assert_eq!(結末.モデル.遷移一覧().len(), 6, "名前が2種類しか無くても、状態3件 × コマンド2件の6件の遷移を組まなければならない");
    let 数え上げの網羅性::異なる値を同じ名指しへ畳んだ { 畳まれた名指しの表記一覧 } = &結末.網羅性 else {
        panic!("互いに等しくない2つの状態が同じ名指しへ写ったのに網羅性が畳みを名乗らなかった: {}", 結末.網羅性.表記());
    };
    assert!(!畳まれた名指しの表記一覧.is_empty(), "畳まれた名指しの表記が1件も残っていない");
}

#[test]
fn 同じ名前へ写る別の状態を同一性まで畳む領域では網羅性が全件を名乗らない() {
    let 領域 = 歩数を動かす領域::生成する(2, 状態の名指し方::偶奇だけで名指す, 状態の同一性の写し方::偶奇へ畳む);
    let 結末 = 領域から遷移モデルを組む(&領域, 探索の上限::default());
    let 数え上げの網羅性::異なる状態を同じ同一性へ畳んだ { 畳まれた状態の名前一覧 } = &結末.網羅性 else {
        panic!("異なる状態が同じ同一性へ写ったのに網羅性が畳みを名乗らなかった: {}", 結末.網羅性.表記());
    };
    assert!(!畳まれた状態の名前一覧.is_empty(), "畳まれた状態の名前が1件も残っていない");
    assert!(!結末.網羅性.全件を数え上げたか(), "畳みが起きた探索が全件を名乗った");
}

