//! 領域が答えた状態の同一性の重複を探索が検出することを固定する試験。
//!
//! 状態の同一性の写し方を選べる `歩数を動かす領域` を使い、同一性が重複と判定されたときに
//! 数え上げの網羅性が全件を名乗らないことと、重複と判定された側の状態の名前が残ることを固定する。
//! 同じ説明の文で失敗する2件の遷移が別の節点へ写ることも、名前が紛れるかどうかの話としてここで見る。
//! 名指しの重複の検出は `名指しの重複` が見る。

use super::super::fixture::{歩数を動かす領域, 状態の同一性の写し方, 状態の名指し方};
use crate::{探索の上限, 数え上げの網羅性, 領域から遷移モデルを組む};

#[test]
fn 同じ名前へ写る別の状態を同一性まで重複としてまとめる領域では網羅性が全件を名乗らない() {
    let 領域 = 歩数を動かす領域::生成する(2, 状態の名指し方::偶奇だけで名指す, 状態の同一性の写し方::偶奇へまとめる);
    let 結果 = 領域から遷移モデルを組む(&領域, 探索の上限::default());
    let 数え上げの網羅性::異なる状態に同じ同一性を与えた { 重複と判定された状態の名前一覧 } = &結果.網羅性 else {
        panic!("異なる状態が同じ同一性へ写ったのに網羅性が重複のまとめを名乗らなかった: {}", 結果.網羅性.表記());
    };
    assert!(!重複と判定された状態の名前一覧.is_empty(), "重複と判定された状態の名前が1件も残っていない");
    assert!(!結果.網羅性.全件を数え上げたか(), "重複のまとめが起きた探索が全件を名乗った");
}

#[test]
fn 重複と判定された状態の名前一覧に捨てられた側の状態が残る() {
    let 領域 = 歩数を動かす領域::生成する(2, 状態の名指し方::歩数をそのまま名指す, 状態の同一性の写し方::偶奇へまとめる);
    let 結果 = 領域から遷移モデルを組む(&領域, 探索の上限::default());
    let 数え上げの網羅性::異なる状態に同じ同一性を与えた { 重複と判定された状態の名前一覧 } = &結果.網羅性 else {
        panic!("異なる状態が同じ同一性へ写ったのに網羅性が重複のまとめを名乗らなかった: {}", 結果.網羅性.表記());
    };
    assert!(
        重複と判定された状態の名前一覧.iter().any(|名前| 名前.contains("第2歩")),
        "重複と判定された状態の名前に捨てられた側の歩数が入っていない: {重複と判定された状態の名前一覧:?}"
    );
}

#[test]
fn 重複のまとめが起きない領域では全件の数え上げが従来どおり全件を数え上げたを名乗る() {
    let 領域 = 歩数を動かす領域::生成する(2, 状態の名指し方::歩数をそのまま名指す, 状態の同一性の写し方::歩数をそのまま写す);
    let 結果 = 領域から遷移モデルを組む(&領域, 探索の上限::default());
    assert_eq!(結果.網羅性, 数え上げの網羅性::全件を数え上げた, "重複のまとめが起きない全件の領域が全件を名乗らなかった");
    assert_eq!(結果.モデル.到達可能な状態一覧を組む().件数(), 3, "第0歩から第2歩までの3件へ到達しなければならない");
}

#[test]
fn 同じ説明の文で失敗する2件の遷移は別の節点へ写る() {
    let 領域 = 歩数を動かす領域::生成する(2, 状態の名指し方::歩数をそのまま名指す, 状態の同一性の写し方::歩数をそのまま写す);
    let 結果 = 領域から遷移モデルを組む(&領域, 探索の上限::default());
    let 失敗の節点一覧: Vec<String> = 結果.モデル.遷移一覧().iter().filter_map(|遷移| 遷移.失敗()).map(|失敗| 失敗.表記()).collect();
    assert_eq!(失敗の節点一覧.len(), 2, "第0歩の戻ると第2歩の進むの2件が失敗した遷移でなければならない: {失敗の節点一覧:?}");
    assert_ne!(失敗の節点一覧[0], 失敗の節点一覧[1], "同じ説明の文の別の失敗が同じ節点へ1つにまとめられている: {失敗の節点一覧:?}");
}
