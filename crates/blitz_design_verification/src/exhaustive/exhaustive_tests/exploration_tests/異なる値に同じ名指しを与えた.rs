//! 領域が答えた、異なる値に同じ名指しを与えたことを探索が検出することを固定する試験。
//!
//! 名指しを単射にしない選び方を選べる `名指しを選ぶ領域` を使い、異なる値に同じ名指しを与えたと判定されたときに
//! 数え上げの網羅性が全件を名乗らないことと、異なる値に与えられた側の名指しの表記が残ることを固定する。
//! 最初の1件だけは、状態の同一性の写し方を選べる `歩数を動かす領域` で名指しだけを衝突させ、
//! 異なる値に同じ名指しを与えたことが異なる状態に同じ同一性を与えたこととは別に検出されることを確かめる。
//! 遷移の識別子が前状態と入力を1本の文字列へ連結しないことも、名指しが紛れるかどうかの話としてここで見る。
//! 異なる状態に同じ同一性を与えたことの検出は `異なる状態に同じ同一性を与えた` が見る。

#![allow(clippy::unwrap_used)]

use super::super::fixture::{初期状態の数え上げ方, 名指しの選び方, 名指しを選ぶ領域, 名指しを選ぶ領域の構成, 歩数を動かす領域, 状態の同一性の写し方, 状態の名指し方};
use crate::{探索が組んだ遷移モデルと網羅性, 探索の上限, 数え上げの網羅性, 設計概念への参照, 領域から遷移モデルを組む};

#[test]
fn 粗く名指す領域は状態を1件も捨てないが網羅性は異なる値に同じ名指しを与えたと名乗る() {
    // 探索そのものは同一性で辿るため、名前が2種類しか無くても3件の状態を辿り切る。
    // ただしモデルの上では別の状態が1件の節点へ重なり、命題の層がその2つを区別できないため、全件は名乗れない。
    let 領域 = 歩数を動かす領域::生成する(2, 状態の名指し方::偶奇だけで名指す, 状態の同一性の写し方::歩数をそのまま写す);
    let 遷移モデルと網羅性 = 領域から遷移モデルを組む(&領域, 探索の上限::default()).unwrap();
    assert_eq!(遷移モデルと網羅性.モデル.遷移一覧().len(), 6, "名前が2種類しか無くても、状態3件 × コマンド2件の6件の遷移を組まなければならない");
    let 数え上げの網羅性::異なる値に同じ名指しを与えた {
        異なる値に与えられた名指しの表記一覧
    } = &遷移モデルと網羅性.網羅性
    else {
        panic!("互いに等しくない2つの状態が同じ名指しへ写ったのに網羅性が異なる値に同じ名指しを与えたと名乗らなかった: {}", 遷移モデルと網羅性.網羅性.表記());
    };
    assert!(!異なる値に与えられた名指しの表記一覧.is_empty(), "異なる値に与えられた名指しの表記が1件も残っていない");
}

#[test]
fn 互いに等しくない2つのコマンドを同じ名指しへ写す領域では網羅性が全件を名乗らない() {
    let 遷移モデルと網羅性 = 名指しの選び方で組んだ遷移モデルと網羅性(名指しの選び方::コマンドを同じ名前にまとめる);
    let 数え上げの網羅性::異なる値に同じ名指しを与えた {
        異なる値に与えられた名指しの表記一覧
    } = &遷移モデルと網羅性.網羅性
    else {
        panic!("2つのコマンドが同じ名指しへ写ったのに網羅性が異なる値に同じ名指しを与えたと名乗らなかった: {}", 遷移モデルと網羅性.網羅性.表記());
    };
    assert!(
        異なる値に与えられた名指しの表記一覧.iter().any(|表記| 表記.contains("同じ名前")),
        "異なる値に与えられた名指しにコマンドの名前が入っていない: {異なる値に与えられた名指しの表記一覧:?}"
    );
}

