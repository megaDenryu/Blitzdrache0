#[test]
fn どれもまとめない領域は従来どおり全件を数え上げたを名乗る() {
    let 遷移モデルと網羅性 = 名指しの選び方で組んだ遷移モデルと網羅性(名指しの選び方::どれも同じ名前にまとめない);
    assert_eq!(
        遷移モデルと網羅性.網羅性,
        数え上げの網羅性::全件を数え上げた,
        "異なる値に同じ名指しを与えたことが1度も起きていない領域が全件を名乗らなかった: {}",
        遷移モデルと網羅性.網羅性.表記()
    );
    assert_eq!(遷移モデルと網羅性.モデル.遷移一覧().len(), 4, "地点2件 × コマンド2件の4件の遷移を組まなければならない");
}

#[test]
fn 繋いだ表記が同じになる2件の遷移も別の遷移として量化される() {
    // 前状態と入力の表記を1本へ繋いだ文字列を識別子にすると、この4件のうち2件が同じ識別子になる。
    let 遷移モデルと網羅性 = 名指しの選び方で組んだ遷移モデルと網羅性(名指しの選び方::繋いだ表記が紛れる名前にする);
    let 遷移一覧 = 遷移モデルと網羅性.モデル.到達可能な遷移一覧();
    assert_eq!(遷移一覧.len(), 4, "地点2件 × コマンド2件の4件が到達可能な遷移でなければならない");
    let 繋いだ表記一覧: Vec<String> = 遷移一覧.iter().map(|遷移| 遷移.識別子().表記()).collect();
    assert!(
        繋いだ表記一覧.iter().any(|表記| 繋いだ表記一覧.iter().filter(|他| 他 == &表記).count() > 1),
        "この試験は、繋いだ表記が同じになる2件を含む領域を題材にする: {繋いだ表記一覧:?}"
    );
    let 項の参照一覧: Vec<設計概念への参照> = 遷移一覧.iter().map(|遷移| 遷移.識別子().設計概念への参照として表す()).collect();
    for (添字, 参照) in 項の参照一覧.iter().enumerate() {
        assert_eq!(項の参照一覧.iter().filter(|他| 他 == &参照).count(), 1, "{添字}番目の遷移と同じ参照へ写る別の遷移が在る: {}", 参照.表記());
    }
}

/// 名指しの選び方だけを変えて、初期状態は全件で答える領域が組んだ遷移モデルと網羅性。
fn 名指しの選び方で組んだ遷移モデルと網羅性(選び方: 名指しの選び方) -> 探索が組んだ遷移モデルと網羅性 {
    let 領域 = 名指しを選ぶ領域::生成する(名指しを選ぶ領域の構成 {
        名指しの選び方: 選び方,
        初期状態の数え上げ方: 初期状態の数え上げ方::全件で答える,
    });
    領域から遷移モデルを組む(&領域, 探索の上限::default()).unwrap()
}
