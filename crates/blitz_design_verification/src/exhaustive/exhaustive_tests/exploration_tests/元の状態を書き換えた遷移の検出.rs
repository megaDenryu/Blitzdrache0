//! 失敗した遷移が遷移失敗結果の元の状態へ受け取った状態と異なる値を入れて返したとき、探索が遷移モデルを返さずにその食い違いを報告することを固定する試験。
//! 型は元の状態と受け取った状態の等しさを保証しないため、探索がすべての失敗した遷移で確かめる(設計オントロジー 3.5.9)。

#![allow(clippy::unwrap_used)]

use super::super::fixture::元の状態を書き換える領域;
use crate::{探索の上限, 領域から遷移モデルを組む};

#[test]
fn 元の状態を書き換えて返す失敗の遷移があれば探索は遷移モデルを返さず食い違った遷移を報告する() {
    // 上限1の領域では、第1目盛りからの進める操作だけが失敗し、その元の状態が第0目盛りへ書き換わる。
    let 食い違い = 領域から遷移モデルを組む(&元の状態を書き換える領域::生成する(1), 探索の上限::default()).unwrap_err();
    assert_eq!(食い違い.食い違った遷移一覧().len(), 1, "食い違った遷移は第1目盛りからの進める操作の1件だけである: {食い違い}");
    let 食い違った遷移 = &食い違い.食い違った遷移一覧()[0];
    assert!(食い違った遷移.前状態().表記().contains("第1目盛り"), "食い違った遷移の前状態が第1目盛りでない: {}", 食い違った遷移.表記());
    assert!(食い違い.to_string().contains("3.5.9"), "報告の文が破られた契約の出典を言わない: {食い違い}");
}

#[test]
fn 書き換えた元の状態が受け取った状態と等しいなら食い違いにならない() {
    // 上の試験が空虚に通らないこと(差し替え自体ではなく、受け取った状態との食い違いを見ていること)を確かめる。
    // 上限0の領域では第0目盛りからの進める操作が失敗し、第0目盛りへ差し替えても受け取った状態と等しい。
    let 結果 = 領域から遷移モデルを組む(&元の状態を書き換える領域::生成する(0), 探索の上限::default()).unwrap();
    assert_eq!(結果.モデル.遷移一覧().iter().filter(|遷移| 遷移.失敗().is_some()).count(), 1, "第0目盛りからの進める操作が失敗した遷移として残っていない");
}
