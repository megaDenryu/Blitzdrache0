//! 探索の辿りそのものを固定する試験。
//!
//! 探索が実物の遷移の口を呼んで遷移を組むことと、数え上げが標本に限ると名乗ったときに結末の網羅性がそれを引き継ぐことと、
//! 上限に達したときに打ち切りを名乗ることと、失敗した遷移が出来事を1件も生成しないことと、
//! 初期状態が標本に限るときも網羅性がそれを引き継ぐことを見る。

#![allow(clippy::unwrap_used)]

use super::super::fixture::{初期状態の数え上げ方, 名指しの選び方, 名指しを選ぶ領域, 名指しを選ぶ領域の構成, 目盛りを進める領域};
use crate::{探索の上限, 数え上げの網羅性, 遷移, 領域から遷移モデルを組む};

#[test]
fn 探索は初期状態から遷移を組み数え上げが標本に限るなら網羅性もそれを引き継ぐ() {
    let 領域 = 目盛りを進める領域::生成する(3);
    let 結末 = 領域から遷移モデルを組む(&領域, 探索の上限::default());
    assert_eq!(結末.モデル.初期状態一覧().len(), 1, "初期状態は1件でなければならない");
    assert_eq!(結末.モデル.到達可能な状態一覧を組む().件数(), 4, "第0目盛りから第3目盛りまでの4件へ到達しなければならない");
    assert_eq!(結末.モデル.遷移一覧().len(), 8, "状態4件 × コマンド2件の8件の遷移を組まなければならない");
    let 数え上げの網羅性::連続量の標本に限る { 説明一覧 } = &結末.網羅性 else {
        panic!("数え上げが標本に限ると名乗ったのに網羅性が全件を名乗った: {}", 結末.網羅性.表記());
    };
    assert_eq!(説明一覧.len(), 1, "同じ説明の文は1度だけ残さなければならない");
}

#[test]
fn 探索の上限に達したら網羅性は上限で打ち切ったを名乗る() {
    let 領域 = 目盛りを進める領域::生成する(3);
    let 結末 = 領域から遷移モデルを組む(&領域, 探索の上限::生成する(0));
    assert_eq!(結末.網羅性, 数え上げの網羅性::上限で打ち切った { 上限: 0 }, "上限に達した探索が打ち切りを名乗らなかった");
}

#[test]
fn 上限まで進めた目盛りからの進める操作は失敗した遷移になり出来事を1件も生成しない() {
    let 領域 = 目盛りを進める領域::生成する(1);
    let 結末 = 領域から遷移モデルを組む(&領域, 探索の上限::default());
    let 失敗した遷移一覧: Vec<&遷移> = 結末.モデル.遷移一覧().iter().filter(|遷移| 遷移.失敗().is_some()).collect();
    assert_eq!(失敗した遷移一覧.len(), 1, "第1目盛りからの進める操作だけが失敗した遷移でなければならない");
    assert!(失敗した遷移一覧[0].生成した出来事一覧().is_empty(), "失敗した遷移は出来事を1件も生成しない");
    assert_eq!(失敗した遷移一覧[0].後状態(), 失敗した遷移一覧[0].前状態(), "失敗した遷移の後状態は前状態と同じである");
}

#[test]
fn 同じ説明の文で失敗する2件の遷移は別の節点へ写る() {
    let 領域 = 歩数を動かす領域::生成する(2, 状態の名指し方::歩数をそのまま名指す, 状態の同一性の写し方::歩数をそのまま写す);
    let 結末 = 領域から遷移モデルを組む(&領域, 探索の上限::default());
    let 失敗の節点一覧: Vec<String> = 結末.モデル.遷移一覧().iter().filter_map(|遷移| 遷移.失敗()).map(|失敗| 失敗.表記()).collect();
    assert_eq!(失敗の節点一覧.len(), 2, "第0歩の戻ると第2歩の進むの2件が失敗した遷移でなければならない: {失敗の節点一覧:?}");
    assert_ne!(失敗の節点一覧[0], 失敗の節点一覧[1], "同じ説明の文の別の失敗が同じ節点へ畳まれている: {失敗の節点一覧:?}");
}

#[test]
fn 初期状態を標本で答える領域では網羅性が連続量の標本に限るになる() {
    // 初期状態が代表の標本でしかないのに全件を名乗ると、見ていない初期状態についての全称が証明済みになる(Major F)。
    let 領域 = 名指しを選ぶ領域::生成する(名指しを選ぶ領域の構成 {
        名指しの選び方: 名指しの選び方::どれも畳まない,
        初期状態の数え上げ方: 初期状態の数え上げ方::連続量を含む標本で答える,
    });
    let 結末 = 領域から遷移モデルを組む(&領域, 探索の上限::default());
    let 数え上げの網羅性::連続量の標本に限る { 説明一覧 } = &結末.網羅性 else {
        panic!("初期状態が標本に限るのに網羅性が全件を名乗った: {}", 結末.網羅性.表記());
    };
    assert!(説明一覧.iter().any(|説明| 説明.contains("初期の地点")), "初期状態の標本の説明が網羅性へ積まれていない: {説明一覧:?}");
}
