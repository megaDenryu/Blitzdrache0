//! 関数の引数と戻り値の役目とは、関数の役割の宣言の型引数の位置ごとに、関数がその型を何の役目で受け取るか返すかを表す設計の関係の語のことである(2026-09-30 オーナー裁定)。
//! 語は4つであり、`変換用の素材にする`・`生成する`・`参照する`・`書き換える` である。定義の式は、関数の役割の宣言の型引数の位置からだけこの4語を導く(`導出/役割の型引数の規則表.rs`)。
//!
//! **`変換用の素材にする` は値が消えることを言わない。** 関数がその回の結果へ作り変える元として受け取る入力であることを言う(遷移は今の状態と命令を変換用の素材にする)。
//! 変わらない前提として読むだけの `参照する` と対になる。旧称は `変換用の素材にする` であり、使って消えると読まれるため改めた。
//!
//! **`識別する` はこの型に入れない。** `識別する` は `impl Mエンティティ for 型 { type 識別子 = …; }` から導く、エンティティとその目印の型のつながりであり、
//! 関数の引数でも戻り値でもない。`識別する` と、この型の4語を並べる入れ物は `設計関係の結び付き方` である。
//! 参照: `_doc/設計/設計オントロジー.md` 6.5節。

use super::設計関係の結び付き方;

/// 関数の役割の宣言の型引数の位置が表す、関数がその型を受け取るか返すかの役目。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum 関数の引数と戻り値の役目 {
    /// 主語の処理が目的語を、その回の結果へ作り変える元として受け取る。
    変換用の素材にする,
    /// 主語の処理が目的語を出力として作る。
    生成する,
    /// 主語の処理が目的語を変わらない前提として読むだけである。
    参照する,
    /// 主語の処理が、目的語の状態をゲームの規則によらず外からの材料で書き換えた値として返す。
    書き換える,
}

impl 関数の引数と戻り値の役目 {
    /// 役目の4語の全件。
    pub const fn 全部() -> [Self; 4] {
        [Self::変換用の素材にする, Self::生成する, Self::参照する, Self::書き換える]
    }

    /// 人が読む語。報告と試験の判定がこの語を使う。
    pub const fn 語(self) -> &'static str {
        match self {
            Self::変換用の素材にする => "変換用の素材にする",
            Self::生成する => "生成する",
            Self::参照する => "参照する",
            Self::書き換える => "書き換える",
        }
    }

    /// この役目を、識別すると並ぶ設計関係の結び付き方として見た値。設計関係の辺と原子命題と欠落はこの値で種類を持つ。
    pub const fn 設計関係の結び付き方へ写す(self) -> 設計関係の結び付き方 {
        設計関係の結び付き方::関数の引数と戻り値の役目(self)
    }
}
