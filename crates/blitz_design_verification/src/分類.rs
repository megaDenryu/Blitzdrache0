//! 分類の事実と節点の分類。
//!
//! 節点の分類とは、設計関係グラフの節点ごとに、その型が持つ分類を引ける索引のことである。分類とは、型が実装した設計解釈マーカーの集合を、
//! 上位トレイトの宣言で閉じたもののことである(`M状態` を実装した型は `M不変データ` も持つ)。
//!
//! **閉包は事実から計算する。** 公理(分類どうしの一種であるという関係)の正本は上位トレイトの宣言の事実であり、この型は公理の表を持たない。
//! 閉じた分類には `M不変データ: Clone` の `Clone` のような標準のトレイトも入る。コンパイラが同じ上位トレイトの宣言で強制するためである。
//! 分類を持つのは、マーカーの実装の事実の主語に立つ型だけである。トレイトは分類を持たない。`trait M不変エンティティ: Mエンティティ` を
//! `Mエンティティ` を持つ概念として数えると、そのマーカーを実装した型が1件も無くても母集団へトレイトが入るためである。
//!
//! **分類は設計関係への参加に数えない。** 分類は辺ではないため、`設計関係グラフ::関係へ1つも参加していないか` はこの索引を読まない。
//! 参照: Issue #193「分類と公理」。

#[path = "分類/事実.rs"]
mod 事実;
#[cfg(test)]
#[path = "分類/節点の分類の試験.rs"]
mod 節点の分類の試験;

use std::collections::{HashMap, HashSet};

use crate::設計概念への参照;

pub use 事実::{マーカーの実装の事実, 上位トレイトの宣言の事実, 事実の出どころ, 分類の事実};

/// 型ごとの閉じた分類の索引と、それを組んだ分類の事実。
#[derive(Debug, Clone, Default)]
pub struct 節点の分類 {
    事実: 分類の事実,
    型ごとの分類: Vec<(設計概念への参照, Vec<設計概念への参照>)>, // マーカーの実装の事実に型が初めて現れた順
    索引: HashMap<設計概念への参照, usize>,                       // 型から `型ごとの分類` の添字を引く
    事実に現れる参照: HashSet<設計概念への参照>,
}

impl 節点の分類 {
    /// 分類の事実から、型ごとの分類を上位トレイトの宣言で閉じて組む。
    pub(crate) fn 事実から閉包を取って生成する(事実: 分類の事実) -> Self {
        let mut 上位の表: HashMap<&設計概念への参照, Vec<&設計概念への参照>> = HashMap::new();
        for 宣言 in 事実.上位トレイトの宣言一覧() {
            上位の表.entry(&宣言.トレイト).or_default().push(&宣言.上位トレイト);
        }
        let mut 型ごとの分類: Vec<(設計概念への参照, Vec<設計概念への参照>)> = Vec::new();
        let mut 索引 = HashMap::new();
        for 実装 in 事実.マーカーの実装一覧() {
            let 添字 = *索引.entry(実装.型.clone()).or_insert_with(|| {
                型ごとの分類.push((実装.型.clone(), Vec::new()));
                型ごとの分類.len() - 1
            });
            let 分類 = &mut 型ごとの分類[添字].1;
            for トレイト in 上位へ閉じる(&上位の表, &実装.マーカー) {
                if !分類.contains(&トレイト) {
                    分類.push(トレイト);
                }
            }
        }
        let 事実に現れる参照 = 事実
            .マーカーの実装一覧()
            .iter()
            .flat_map(|実装| [&実装.型, &実装.マーカー])
            .chain(事実.上位トレイトの宣言一覧().iter().flat_map(|宣言| [&宣言.トレイト, &宣言.上位トレイト]))
            .cloned()
            .collect();
        Self {
            事実, 型ごとの分類, 索引, 事実に現れる参照
        }
    }

    /// この索引を組んだ分類の事実。
    pub fn 事実を貸す(&self) -> &分類の事実 {
        &self.事実
    }

    /// その概念の閉じた分類。分類を持たない概念では空を返す。
    pub fn 概念の分類(&self, 概念: &設計概念への参照) -> &[設計概念への参照] {
        self.索引.get(概念).map_or(&[], |添字| self.型ごとの分類[*添字].1.as_slice())
    }

    /// その概念の閉じた分類が、そのトレイトを含むか。
    pub fn 分類がトレイトを含むか(&self, 概念: &設計概念への参照, トレイト: &設計概念への参照) -> bool {
        self.概念の分類(概念).contains(トレイト)
    }

    /// 閉じた分類にその名前のトレイトを含む概念の一覧。命題がマーカーを名前で名指すため、名前で照合する。
    pub fn 名前のトレイトを分類に持つ概念一覧(&self, 名前: &str) -> Vec<&設計概念への参照> {
        self.型ごとの分類.iter().filter(|(_, 分類)| 分類.iter().any(|トレイト| トレイト.識別子().名前 == 名前)).map(|(型, _)| 型).collect()
    }

    /// その参照が、分類の事実のどれかに型・マーカー・トレイト・上位トレイトとして現れるか。
    pub fn 事実に現れるか(&self, 参照: &設計概念への参照) -> bool {
        self.事実に現れる参照.contains(参照)
    }
}

// 起点のトレイトと、起点から上位トレイトの宣言を辿って達するトレイトの全部。同じトレイトを2度は辿らない。
fn 上位へ閉じる(上位の表: &HashMap<&設計概念への参照, Vec<&設計概念への参照>>, 起点: &設計概念への参照) -> Vec<設計概念への参照> {
    let mut 達した: Vec<設計概念への参照> = Vec::new();
    let mut 待ち = vec![起点];
    while let Some(いま) = 待ち.pop() {
        if 達した.contains(いま) {
            continue;
        }
        達した.push(いま.clone());
        待ち.extend(上位の表.get(いま).into_iter().flatten().copied());
    }
    達した
}
