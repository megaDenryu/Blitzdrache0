//! 命題の検証器の口と、原子と対象集合だけを解く役の口(Issue #173。層4)。
//!
//! **`bool` を返す口を1つも作らない。** 検証器の口は `検証する` の1つだけであり、答えは必ず3値の `検証結果` である。
//! 記号実行とSMTの検証器を後から足せるようにするため、検証器ごとの入力(設計関係グラフ・遷移モデル)は
//! トレイトの引数でなくその検証器自身のフィールドが保持する。引数で受けると、口が増えるたびに全部の検証器の署名が変わる。
//!
//! **結合(否定・連言・選言・含意・全称・存在)の規則の正本は1つである。** 検証器ごとに書き写すと、
//! 片方だけが未決定を偽へ潰した食い違いが出るまで見つからない。各検証器は `原子と対象集合の解き手` だけを実装し、
//! 結合は `結合を解く工程` へ委譲する。
//! 参照: `_doc/設計/設計オントロジー.md` 第9節。

mod combination;
