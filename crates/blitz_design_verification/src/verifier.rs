/// 命題1つを受けて3値で答える口。
pub trait 命題の検証器 {
    /// この命題をこの検証器が解ける範囲で検証する。解けない式は偽でなく未決定で答える。
    fn 検証する(&self, 命題: &命題) -> 検証結果;
}

/// 結合を解かず、原子命題と対象集合の列挙だけを答える役。検証器ごとに違うのはこの3つだけである。
pub trait 原子と対象集合の解き手 {
    /// この解き手が示した証拠と反例が名乗る検証の方式。
    fn 方式(&self) -> 検証の方式;

    /// 原子命題1つを、束縛の割り当てのもとで解く。この解き手が扱わない原子命題は未決定で答える。
    fn 原子を解く(&self, 原子: &原子命題, 割り当て: &束縛の割り当て) -> 検証結果;

    /// 対象集合を有限に列挙する。列挙できない対象集合は未決定の理由で答える。
    fn 対象集合を列挙する(&self, 対象: &対象集合) -> Result<列挙した対象, 未決定の理由>;
}

/// 対象集合を列挙した結果。呼び名を一緒に持つのは、証拠と反例の説明へ「何を何件見たか」を必ず残すためである。
/// 網羅性を一緒に持つのは、並べた件数だけでは「取りうる値の全部」と「取りうる値の一部の標本」を量化の畳み込みが区別できないためである。
pub struct 列挙した対象 {
    /// 「到達可能な遷移」のような、証拠の説明へ入れる呼び名。
    pub 呼び名: String,
    /// 実際に並べた対象の識別子。
    pub 識別子一覧: Vec<設計概念の識別子>,
    /// この並びが取りうる値の全件であるか、標本に限るか、上限で打ち切ったか。
    pub 網羅性: 数え上げの網羅性,
}
