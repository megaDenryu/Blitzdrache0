//! 設計概念の識別用情報とは、設計概念の識別子に設計概念の種類を添えた、設計関係の端点と命題の項と量化の割り当てが指す1つの設計概念の指定のことである。
//! 指し先がグラフに実在するとは限らない。
//! 設計概念の識別子は同一性だけを持ち種類を持たないが、設計概念の識別用情報は種類まで持ち、等価の判定に種類も使う点で違う。
//!
//! **識別子の側へ種類を入れず、識別用情報の側が種類を持つ。** 識別子へ種類を入れると、同じ識別子へ種類の違う概念が現れるという事象が
//! 原理的に起こらなくなり、`設計関係グラフ` の組み立てが数える同一性の衝突が到達しない分岐になる。そのうえ抽出器は目的語の種類を
//! 推測しており(関数の役割の規則は、役割の型引数から出した目的語を無条件に型として積む)、推測で積んだノードと正しい種類のノードが
//! 別のノードへ割れてエッジが散る。したがって同一性は4つ組のまま残し、端点の側が種類を運ぶ。この2つを両立させる形はこれだけである。
//!
//! **ノード(`設計概念ノード`)と識別用情報は同じ組を持つが別の概念である。** ノードはグラフに実在する1件であり、識別用情報はその1件を指すエッジと項の端点である。
//! ノードは識別用情報を包んだ newtype であり、ノードが在ることは識別用情報が在ることより強い主張である。
//!
//! **2つの識別用情報が同じ1件を指すかの判定は、値の等価(`==`)である。** 等価は識別子と種類の両方を見るため、
//! `型 Foo` を指す識別用情報と `トレイト Foo` を指す識別用情報は等しくない。設計関係グラフの照合もノードの実在の判定もこの等価を使う。
//! 種類を見ずに識別子だけで照合すると、`トレイト Foo` へ張ったエッジを `型 Foo` についての問いが借りて証明済みを答える。
//! 量化の対象の重複を1つにまとめる工程も、この識別用情報全体の等価を使う。
//! 参照: `_doc/設計/設計オントロジー.md` 第6節。

use super::設計概念の識別子の定義::{設計概念の名前空間, 設計概念の識別子};
use super::{Rustの項目の種類, 設計概念の種類};

/// 設計関係の端点と命題の項が指す、1つの設計概念の指定。設計概念の識別子に設計概念の種類を添えたものである。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct 設計概念の識別用情報 {
    識別子: 設計概念の識別子,
    種類: 設計概念の種類,
}

impl 設計概念の識別用情報 {
    /// Rustのソースに定義が在る項目の識別用情報を組む。識別子の名前空間をRustの項目へ据え直すため、名前空間と種類は必ず揃う。
    #[allow(non_snake_case)] // 日本語の識別子に含むASCIIの大文字はRustの命名規則の検査に掛かる。言語の名前をそのまま使う。
    pub fn Rustの項目として生成する(識別子: 設計概念の識別子, 種類: Rustの項目の種類) -> Self {
        Self {
            識別子: 識別子.名前空間を種類に合わせて据える(種類),
            種類: 種類.設計概念の種類へ写す(),
        }
    }

    /// 実行時にだけ存在するドメインの概念の識別用情報を組む。名前空間と種類の両方をここで同時に据える。
    pub fn 実行時のドメイン概念として生成する(名前の空間: &str, 名前: &str) -> Self {
        Self {
            識別子: 設計概念の識別子::実行時のドメイン概念として生成する(名前の空間, 名前),
            種類: 設計概念の種類::実行時のドメイン概念,
        }
    }

    /// 型の識別用情報を組む。
    pub fn 型として生成する(モジュールパス: &str, 名前: &str) -> Self {
        Self::Rustの項目として生成する(設計概念の識別子::Rustの項目として生成する(モジュールパス, 名前), Rustの項目の種類::型)
    }

    /// トレイトの識別用情報を組む。
    pub fn トレイトとして生成する(モジュールパス: &str, 名前: &str) -> Self {
        Self::Rustの項目として生成する(設計概念の識別子::Rustの項目として生成する(モジュールパス, 名前), Rustの項目の種類::トレイト)
    }

    /// 処理の識別用情報を組む。
    pub fn 処理として生成する(モジュールパス: &str, 名前: &str) -> Self {
        Self::Rustの項目として生成する(設計概念の識別子::Rustの項目として生成する(モジュールパス, 名前), Rustの項目の種類::処理)
    }

    /// 所有者の並びを添えた同じ識別用情報。名前の欄だけでは同じになる別物を、名前へまとめずに分けるために要る。
    pub fn 所有者を添える(self, 所有者の並び: Vec<String>) -> Self {
        Self {
            識別子: self.識別子.所有者を添える(所有者の並び),
            種類: self.種類,
        }
    }

    /// この識別用情報が指す概念の同一性。
    pub fn 識別子(&self) -> &設計概念の識別子 {
        &self.識別子
    }

    /// この識別用情報が名乗る種類。
    pub const fn 種類(&self) -> 設計概念の種類 {
        self.種類
    }

    /// 人が読む1行の表記。証拠と反例と違反の報告がこの表記を使う。
    pub fn 表記(&self) -> String {
        self.識別子.表記()
    }

    // 探索が組む状態遷移と失敗の同一性へ埋め込むため、表示を介さず全成分を保存する。
    // 各文字列のバイト長を先に置くため、区切り文字や空文字を含む成分も一意に復元できる。
    pub(crate) fn 同一性を符号化する(&self) -> String {
        let 名前空間 = match self.識別子.名前空間() {
            設計概念の名前空間::Rustの型の名前空間 => "rust-type",
            設計概念の名前空間::Rustの値の名前空間 => "rust-value",
            設計概念の名前空間::実行時のドメイン概念 => "runtime",
        };
        let 種類 = match self.種類 {
            設計概念の種類::型 => "type",
            設計概念の種類::トレイト => "trait",
            設計概念の種類::処理 => "function",
            設計概念の種類::実行時のドメイン概念 => "runtime",
        };
        [名前空間, 種類, self.識別子.モジュールパス(), self.識別子.名前()]
            .into_iter()
            .chain(self.識別子.所有者の並び().iter().map(String::as_str))
            .map(|成分| format!("{}:{成分}", 成分.len()))
            .collect()
    }
}
