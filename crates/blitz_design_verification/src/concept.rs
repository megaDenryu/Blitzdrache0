//! 設計概念とは、設計関係グラフの節点になる、名前を持つ設計上の概念のことである。
//! 型・トレイト・処理の3種を1つの節点の型で表すのは、設計関係の主語と目的語がこの3種を区別せずに取るためである
//! (`旅行者ID 識別する 旅行者` は型と型、`M状態 下位型である M不変データ` はトレイトとトレイト、`移動の解釈 生成する 移動コマンド` は処理と型を結ぶ)。
//!
//! 同一性は「名前空間 + 定義のモジュールパス + 所有者の並び + 名前」の4つである。1本の文字列へ畳まないのは、クレートだけで絞る問いと
//! 名前だけで絞る問いの両方が在り、畳むと問うたびに文字列を切り直すことになるためである。
//!
//! **`設計概念の種類` は同一性へ入れない。** 理由は2つある。1つは、種類を同一性へ入れると「同じ識別子で種類が違う」という事象が
//! 原理的に起こらなくなり、`設計関係グラフ` の組み立てが返す同一性の衝突の報告が到達しない枝になることである。
//! もう1つは、抽出器が目的語の種類を推測していることである(`xtask` の関数の役割の規則は、役割の型引数から出した目的語を
//! 無条件に型として積む)。種類を同一性へ入れると、同じものが種類の違う2つの節点へ割れて辺が散る。
//! 黙って1件へ畳む害よりも、黙って割れる害の方が大きい。
//! 参照: `_doc/設計/設計オントロジー.md` 第6節。

/// 設計関係グラフの節点1つ。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct 設計概念 {
    /// 名前空間とモジュールパスと所有者の並びと名前の4つ組。
    pub 識別子: 設計概念の識別子,
    /// 型・トレイト・処理のどれであるか。
    pub 種類: 設計概念の種類,
}

/// 設計概念が型・トレイト・処理のどれであるか。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum 設計概念の種類 {
    /// 構造体・列挙・newtype のように、値の形を定める定義。
    型,
    /// トレイトの定義。設計解釈マーカーもこれである。
    トレイト,
    /// 関数の役割の型引数が付いた処理の定義。
    処理,
}

/// 設計概念の名前が住む空間。Rustのソースに定義が在る項目と、実行時にだけ存在するドメインの概念を区別する。
/// この区別が要るのは、実行時のドメイン概念にはモジュールパスが無く、定義をたどれずモジュールパスが空になった
/// Rustの型と同じ形になるためである。空文字を「Rustの型ではない」という意味へ密輸しない。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum 設計概念の名前空間 {
    /// Rustのソースに定義が在る項目。モジュールパスは定義の位置を指す。
    Rustの項目,
    /// 実行時にだけ存在するドメインの概念。Rustの型であるとは限らず、モジュールパスは名前の空間として使う。
    実行時のドメイン概念,
}

/// 設計概念の同一性。名前空間と定義のモジュールパスと所有者の並びと名前の4つ組である。
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct 設計概念の識別子 {
    /// Rustの項目か、実行時のドメイン概念か。
    pub 名前空間: 設計概念の名前空間,
    /// `blitz_esca::traveler` の形。`crates` の下に無いものと、定義をたどれなかったものは空である。
    pub モジュールパス: String,
    /// その名前を所有する型の並び。関連関数なら所有する型の名前が入り、無ければ空である。
    pub 所有者の並び: Vec<String>,
    /// 型引数を落とした先頭の識別子。`遷移成功結果<状態, イベント>` なら `遷移成功結果` である。
    pub 名前: String,
}

impl 設計概念の識別子 {
    /// Rustのソースに定義が在る項目の識別子を組む。所有者の並びは空である。
    #[allow(non_snake_case)] // 日本語の識別子に含むASCIIの大文字はRustの命名規則の検査に掛かる。言語の名前をそのまま使う。
    pub fn Rustの項目として生成する(モジュールパス: &str, 名前: &str) -> Self {
        Self::名前空間を決めて生成する(設計概念の名前空間::Rustの項目, モジュールパス, 名前)
    }

    /// 実行時にだけ存在するドメインの概念の識別子を組む。名前の空間には、その概念を語る型が居るモジュールを渡してよく、空でもよい。
    pub fn 実行時のドメイン概念として生成する(名前の空間: &str, 名前: &str) -> Self {
        Self::名前空間を決めて生成する(設計概念の名前空間::実行時のドメイン概念, 名前の空間, 名前)
    }

    /// 所有者の並びを添えた識別子。`旅行者::更新する` と `世界::更新する` のように、名前だけでは同じになる別物を分けるために要る。
    pub fn 所有者を添える(self, 所有者の並び: Vec<String>) -> Self {
        Self { 所有者の並び, ..self }
    }

    fn 名前空間を決めて生成する(名前空間: 設計概念の名前空間, モジュールパス: &str, 名前: &str) -> Self {
        Self {
            名前空間,
            モジュールパス: モジュールパス.to_string(),
            所有者の並び: Vec::new(),
            名前: 名前.to_string(),
        }
    }

    /// 最上位のクレート名。モジュールパスが空なら空である。
    pub fn クレート名(&self) -> &str {
        self.モジュールパス.split("::").next().unwrap_or_default()
    }

    /// Rustの項目でありながら定義のモジュールパスを解決できていないか。抽出器がたどれなかった型の節点がこれである。
    /// 実行時のドメイン概念はモジュールパスが空でも未解決ではないため、偽の未決定を出さないようこの問いで分ける。
    #[allow(non_snake_case)] // 日本語の識別子に含むASCIIの大文字はRustの命名規則の検査に掛かる。言語の名前をそのまま使う。
    pub fn Rustの項目でありながら定義をたどれていないか(&self) -> bool {
        self.名前空間 == 設計概念の名前空間::Rustの項目 && self.モジュールパス.is_empty()
    }

    /// 人が読む1行の表記。違反と反例の報告がこの表記を使う。モジュールパスと所有者の並びと名前を `::` で繋ぎ、空の欄は落とす。
    pub fn 表記(&self) -> String {
        let mut 表記の要素一覧 = Vec::new();
        if !self.モジュールパス.is_empty() {
            表記の要素一覧.push(self.モジュールパス.clone());
        }
        表記の要素一覧.extend(self.所有者の並び.iter().cloned());
        表記の要素一覧.push(self.名前.clone());
        表記の要素一覧.join("::")
    }
}

impl 設計概念 {
    /// 型の節点を組む。
    pub fn 型として生成する(モジュールパス: &str, 名前: &str) -> Self {
        Self {
            識別子: 設計概念の識別子::Rustの項目として生成する(モジュールパス, 名前),
            種類: 設計概念の種類::型,
        }
    }

    /// トレイトの節点を組む。
    pub fn トレイトとして生成する(モジュールパス: &str, 名前: &str) -> Self {
        Self {
            識別子: 設計概念の識別子::Rustの項目として生成する(モジュールパス, 名前),
            種類: 設計概念の種類::トレイト,
        }
    }

    /// 処理の節点を組む。
    pub fn 処理として生成する(モジュールパス: &str, 名前: &str) -> Self {
        Self {
            識別子: 設計概念の識別子::Rustの項目として生成する(モジュールパス, 名前),
            種類: 設計概念の種類::処理,
        }
    }
}
