//! 設計概念とは、設計関係グラフの節点になる、名前を持つ設計上の概念のことである。
//! 型・トレイト・処理・実行時のドメイン概念の4種を1つの節点の型で表すのは、設計関係の主語と目的語がこの4種を区別せずに取るためである
//! (`旅行者ID 識別する 旅行者` は型と型、`M状態 下位型である M不変データ` はトレイトとトレイト、
//! `ゲーム世界の実行時個体ID 識別する ゲーム世界の個体` は型と実行時のドメイン概念を結ぶ)。
//!
//! **節点は `設計概念への参照` を包んだ newtype である。** 節点と参照は識別子と種類の同じ組を持つが、節点はグラフに実在する1件であり、
//! 参照はその1件を指す端点であって指し先が実在するとは限らない。組を2度宣言せず包むのは、辺と項が指す先を節点そのものから作るメソッド
//! (`参照を組む`)を通すことで、節点と端点が別の種類を名乗る組み立てを減らすためである。
//!
//! **名前空間と種類は必ず揃う。** 実行時のドメイン概念の種類を名乗れるのは `実行時のドメイン概念として生成する` だけであり、
//! その関数は名前空間も同時に据える。Rustの項目の節点を組む関数は受け取った識別子の名前空間をRustの項目へ据え直す。
//! フィールドを私有にするのは、構造体リテラルでこの2つの関数を迂回し、名前空間が `Rustの項目` でありながら種類が
//! `実行時のドメイン概念` である節点を組めないようにするためである。
//!
//! **`設計概念の種類` は同一性へ入れない。** 種類を同一性へ入れると「同じ識別子で種類が違う」という事象が原理的に起こらなくなり、
//! `設計関係グラフ` の組み立てが返す同一性の衝突の報告が到達しない分岐になる。同一性を識別子だけで決めるからこそ、
//! 抽出器が目的語の種類を推測して外した箇所(`xtask` の関数の役割の規則は、役割の型引数から出した目的語を無条件に型として積む)が
//! 衝突として名指しで数えられ、`関係を落とした抽出の欠落` を通って不在に由来する結果が未決定へ倒れる。
//! 種類は同一性でなく `設計概念への参照` が運び、グラフへの問いと節点の実在の判定は識別子と種類の両方を見る。
//! 参照: `_doc/設計/設計オントロジー.md` 第6節。

mod identifier;
mod reference;

pub use identifier::{設計概念の名前空間, 設計概念の識別子};
pub use reference::設計概念への参照;

/// 設計関係グラフの節点1つ。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct 設計概念(設計概念への参照);

/// 設計概念が型・トレイト・処理・実行時のドメイン概念のどれであるか。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum 設計概念の種類 {
    /// 構造体・列挙・newtype のように、値の形を定める定義。
    型,
    /// トレイトの定義。設計解釈マーカーもこれである。
    トレイト,
    /// 関数の役割の型引数が付いた処理の定義。
    処理,
    /// Rustの項目として定義が在るとは限らない、実行時にだけ存在するドメインの概念。
    実行時のドメイン概念,
}

/// Rustのソースに定義が在る項目が取りうる種類。実行時のドメイン概念を含まないのは、
/// 抽出器が渡せる種類をこの3つへ型で限り、名前空間と種類の食い違う節点を組ませないためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[allow(non_snake_case)] // 日本語の識別子に含むASCIIの大文字はRustの命名規則の検査に掛かる。言語の名前をそのまま使う。
pub enum Rustの項目の種類 {
    /// 構造体・列挙・newtype のように、値の形を定める定義。
    型,
    /// トレイトの定義。設計解釈マーカーもこれである。
    トレイト,
    /// 関数の役割の型引数が付いた処理の定義。
    処理,
}

impl Rustの項目の種類 {
    /// 節点が持つ種類へ写す。
    pub const fn 設計概念の種類へ写す(self) -> 設計概念の種類 {
        match self {
            Self::型 => 設計概念の種類::型,
            Self::トレイト => 設計概念の種類::トレイト,
            Self::処理 => 設計概念の種類::処理,
        }
    }
}

impl 設計概念 {
    /// Rustのソースに定義が在る項目の節点を組む。識別子の名前空間をRustの項目へ据え直すため、名前空間と種類は必ず揃う。
    #[allow(non_snake_case)] // 日本語の識別子に含むASCIIの大文字はRustの命名規則の検査に掛かる。言語の名前をそのまま使う。
    pub fn Rustの項目として生成する(識別子: 設計概念の識別子, 種類: Rustの項目の種類) -> Self {
        Self(設計概念への参照::Rustの項目として生成する(識別子, 種類))
    }

    /// 実行時にだけ存在するドメインの概念の節点を組む。名前空間と種類の両方をここで同時に据える。
    pub fn 実行時のドメイン概念として生成する(名前の空間: &str, 名前: &str) -> Self {
        Self(設計概念への参照::実行時のドメイン概念として生成する(名前の空間, 名前))
    }

    /// 型の節点を組む。
    pub fn 型として生成する(モジュールパス: &str, 名前: &str) -> Self {
        Self(設計概念への参照::型として生成する(モジュールパス, 名前))
    }

    /// トレイトの節点を組む。
    pub fn トレイトとして生成する(モジュールパス: &str, 名前: &str) -> Self {
        Self(設計概念への参照::トレイトとして生成する(モジュールパス, 名前))
    }

    /// 処理の節点を組む。
    pub fn 処理として生成する(モジュールパス: &str, 名前: &str) -> Self {
        Self(設計概念への参照::処理として生成する(モジュールパス, 名前))
    }

    /// この節点を指す参照。辺の端点と命題の項は、節点そのものから作ったこの参照を持つ。
    pub fn 参照を組む(&self) -> 設計概念への参照 {
        self.0.clone()
    }

    /// この節点が包む参照を貸す。参照が指す先とこの節点が同じ1件であるかを、複製せずに照合するために在る。
    pub fn 参照を貸す(&self) -> &設計概念への参照 {
        &self.0
    }

    /// この節点の同一性。
    pub fn 識別子(&self) -> &設計概念の識別子 {
        self.0.識別子()
    }

    /// この節点が型・トレイト・処理・実行時のドメイン概念のどれであるか。
    pub const fn 種類(&self) -> 設計概念の種類 {
        self.0.種類()
    }
}
