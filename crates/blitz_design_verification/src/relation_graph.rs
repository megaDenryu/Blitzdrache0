//! 設計関係グラフとは、設計概念を節点、設計関係を有向の辺、分類を節点のラベルとして持つ、検証の対象になるグラフのことである。
//! 分類(マーカーの実装を上位トレイトの宣言で閉じたもの)を辺にしないのは、それが2つの概念のあいだの関係ではないためである(`節点の分類`)。
//! 命題の検証器はこのグラフへ問いを投げるだけであり、Rustのソースを1度も読み直さない。ソースを読む工程(抽出器)と
//! 問いに答える工程(このグラフ)を分けるのは、抽出が信頼基盤であって検証の正しさと別に回帰試験で固定する対象だからである。
//!
//! **問いの照合は端点の同一性と種類の両方で行う。** 辺の端点も命題の項も `設計概念への参照` であり、その等価は識別子と種類の両方を見る。
//! 識別子だけで照合すると、`トレイト Foo` から張った1本の辺を「`型 Foo` からその辺が在るか」という問いが借りて証明済みを答える。
//! 種類まで照合した結果として、抽出器が目的語の種類を推測して外した辺は問いから消える。消えた辺の受け止め方は2つ在り、
//! どちらも反証済みへは落ちない。正しい種類の節点も在るなら `設計関係グラフ::生成する` が同一性の衝突として数え、
//! それが `関係を落とした抽出の欠落` を通って不在に由来する結果を未決定へ倒す。正しい種類の節点が無いなら、
//! 組み立てが節点の無い端点を記録してその辺を除き、構造の検証器が不在を根拠にした結果を未決定へ倒す。分類の事実の端点も同じに扱う。
//!
//! 組み立てた設計関係グラフと同一性の衝突をこのファイルが一緒に持つのは、どちらも `設計関係グラフ::生成する` が返すもの以外の何物でもなく、
//! 別ファイルへ移すとデータだけの構造体2つが残って、組み立ての流れを読むのに2ファイルを行き来することになるためである。
//! 参照: `_doc/設計/設計オントロジー.md` 第6節・第7節。

use std::collections::hash_map::Entry;
use std::collections::{HashMap, HashSet};

use super::concept::{設計概念, 設計概念の種類, 設計概念の識別子, 設計概念への参照};
use super::relation::{設計関係, 設計関係の種類};
use crate::{分類の事実, 節点の分類};

#[path = "relation_graph/経路.rs"]
mod 経路;

/// 抽出済みの設計概念と設計関係の全体。
#[derive(Debug, Clone, Default)]
pub struct 設計関係グラフ {
    概念一覧: Vec<設計概念>,
    関係一覧: Vec<設計関係>,
    節点が無い端点一覧: Vec<設計概念への参照>,
    分類: 節点の分類,
}

/// 同じ識別子へ種類の違う概念が現れた1件。先に現れた種類と後から現れた種類の両方を持つ。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 同一性の衝突 {
    /// 衝突した識別子。
    pub 識別子: 設計概念の識別子,
    /// 先に現れた方の種類。
    pub 先に現れた種類: 設計概念の種類,
    /// 後から現れた方の種類。
    pub 後から現れた種類: 設計概念の種類,
}

/// グラフを組み立てた結果。組んだグラフと、そのとき見つけた同一性の衝突の一覧の対である。
/// 衝突を返り値へ載せるのは、黙って1節点へ重複としてまとめたり黙って落としたりせず、呼び出し側に報告させるためである。
#[derive(Debug, Clone, Default)]
pub struct 組み立てた設計関係グラフと同一性の衝突 {
    /// 組み上がったグラフ。
    pub グラフ: 設計関係グラフ,
    /// 組み立ての途中で見つけた同一性の衝突の一覧。
    pub 同一性の衝突一覧: Vec<同一性の衝突>,
}

impl 設計関係グラフ {
    /// 概念と関係の一覧と分類の事実からグラフを組む。同じ識別子で同じ種類の概念は1件にまとめ、種類が違うものは両方を節点として残して衝突に数える。
    /// 種類が違うものを先勝ちでまとめないのは、検証器の節点の同一性を「先に抽出された方」で決めてはならないためである。
    pub fn 生成する(概念一覧: Vec<設計概念>, 関係一覧: Vec<設計関係>, 分類の事実: 分類の事実) -> 組み立てた設計関係グラフと同一性の衝突 {
        let mut 済みの組 = HashSet::new();
        let mut 先に現れた種類 = HashMap::new();
        let mut 重複を除いた概念一覧 = Vec::new();
        let mut 同一性の衝突一覧 = Vec::new();
        for 概念 in 概念一覧 {
            if !済みの組.insert((概念.識別子().clone(), 概念.種類())) {
                continue;
            }
            match 先に現れた種類.entry(概念.識別子().clone()) {
                Entry::Vacant(空き) => {
                    空き.insert(概念.種類());
                }
                Entry::Occupied(先の種類) => 同一性の衝突一覧.push(同一性の衝突 {
                    識別子: 概念.識別子().clone(),
                    先に現れた種類: *先の種類.get(),
                    後から現れた種類: 概念.種類(),
                }),
            }
            重複を除いた概念一覧.push(概念);
        }
        let 節点が在るか = |端点: &設計概念への参照| 済みの組.contains(&(端点.識別子().clone(), 端点.種類()));
        let (分類の事実, 分類の欠けた端点一覧) = 分類の事実.端点に節点が在るものだけを残す(節点が在るか);
        let mut 端点の済み = HashSet::new();
        let 節点が無い端点一覧 = 関係一覧
            .iter()
            .flat_map(|関係| [&関係.主語, &関係.目的語])
            .chain(分類の欠けた端点一覧.iter())
            .filter(|端点| !節点が在るか(*端点) && 端点の済み.insert((*端点).clone()))
            .cloned()
            .collect();
        let 関係一覧 = 関係一覧.into_iter().filter(|関係| 節点が在るか(&関係.主語) && 節点が在るか(&関係.目的語)).collect();
        組み立てた設計関係グラフと同一性の衝突 {
            グラフ: Self {
                概念一覧: 重複を除いた概念一覧,
                関係一覧,
                節点が無い端点一覧,
                分類: 節点の分類::事実から閉包を取って生成する(分類の事実),
            },
            同一性の衝突一覧,
        }
    }

    /// 全ての設計概念。
    pub fn 概念一覧(&self) -> &[設計概念] {
        &self.概念一覧
    }

    /// 全ての設計関係。
    pub fn 関係一覧(&self) -> &[設計関係] {
        &self.関係一覧
    }

    /// 節点ごとの分類の索引。分類は辺ではないため、関係への参加の問いはこれを読まない。
    pub fn 分類を貸す(&self) -> &節点の分類 {
        &self.分類
    }

    /// 組み立て時に、識別子と種類が一致する節点を持たなかった端点。関係の端点と分類の事実の端点の両方を含む。
    pub fn 節点が無い端点一覧(&self) -> &[設計概念への参照] {
        &self.節点が無い端点一覧
    }

    /// その種類の概念だけを集める。
    pub fn 種類で絞った概念一覧(&self, 種類: 設計概念の種類) -> Vec<&設計概念> {
        self.概念一覧.iter().filter(|概念| 概念.種類() == 種類).collect()
    }

    /// その関係が1件でも在るか。命題の原子がこの問いに落ちる。
    pub fn 関係が在るか(&self, 主語: &設計概念への参照, 種類: 設計関係の種類, 目的語: &設計概念への参照) -> bool {
        self.関係一覧.iter().any(|関係| &関係.主語 == 主語 && 関係.種類 == 種類 && &関係.目的語 == 目的語)
    }

    /// 主語と種類を固定したときの目的語の一覧。
    pub fn 目的語一覧(&self, 主語: &設計概念への参照, 種類: 設計関係の種類) -> Vec<&設計概念への参照> {
        self.関係一覧.iter().filter(|関係| &関係.主語 == 主語 && 関係.種類 == 種類).map(|関係| &関係.目的語).collect()
    }

    /// 種類と目的語を固定したときの主語の一覧。
    pub fn 主語一覧(&self, 種類: 設計関係の種類, 目的語: &設計概念への参照) -> Vec<&設計概念への参照> {
        self.関係一覧.iter().filter(|関係| 関係.種類 == 種類 && &関係.目的語 == 目的語).map(|関係| &関係.主語).collect()
    }

    /// その参照が指す節点がグラフに在るか。識別子と種類の両方が一致する節点だけを在ると答える。
    /// 項から節点を求める工程が、命題が名指した概念の実在をこの問いで確かめる。
    pub fn 節点が在るか(&self, 参照: &設計概念への参照) -> bool {
        self.概念一覧.iter().any(|概念| 概念.参照を貸す() == 参照)
    }

    /// その概念が、主語としても目的語としても1つも関係に参加していないか。設計の受理の命題がこの問いを読む。
    /// 分類は辺でないため、マーカーを実装しただけの型は参加に数えない。
    pub fn 関係へ1つも参加していないか(&self, 概念: &設計概念への参照) -> bool {
        !self.関係一覧.iter().any(|関係| &関係.主語 == 概念 || &関係.目的語 == 概念)
    }
}
