//! 設計関係グラフとは、設計概念を節点、設計関係を有向の辺として持つ、検証の対象になるグラフのことである。
//! 命題の検証器はこのグラフへ問いを投げるだけであり、Rustのソースを1度も読み直さない。ソースを読む工程(抽出器)と
//! 問いに答える工程(このグラフ)を分けるのは、抽出が信頼基盤であって検証の正しさと別に回帰試験で固定する対象だからである。
//! 参照: `_doc/設計/設計オントロジー.md` 第6節・第7節。

use std::collections::HashSet;

use super::concept::{設計概念, 設計概念の種類, 設計概念の識別子};
use super::relation::{設計関係, 設計関係の種類};

/// 抽出済みの設計概念と設計関係の全体。
#[derive(Debug, Clone, Default)]
pub struct 設計関係グラフ {
    概念一覧: Vec<設計概念>,
    関係一覧: Vec<設計関係>,
}

impl 設計関係グラフ {
    /// 概念と関係の一覧からグラフを組む。同じ識別子の概念は先に現れたものを残して1件へ畳む。
    pub fn 生成する(概念一覧: Vec<設計概念>, 関係一覧: Vec<設計関係>) -> Self {
        let mut 済み = HashSet::new();
        let 畳んだ概念一覧 = 概念一覧.into_iter().filter(|概念| 済み.insert(概念.識別子.clone())).collect();
        Self {
            概念一覧: 畳んだ概念一覧, 関係一覧
        }
    }

    /// 全ての設計概念。
    pub fn 概念一覧(&self) -> &[設計概念] {
        &self.概念一覧
    }

    /// 全ての設計関係。
    pub fn 関係一覧(&self) -> &[設計関係] {
        &self.関係一覧
    }

    /// その種類の概念だけを集める。
    pub fn 種類で絞った概念一覧(&self, 種類: 設計概念の種類) -> Vec<&設計概念> {
        self.概念一覧.iter().filter(|概念| 概念.種類 == 種類).collect()
    }

    /// その関係が1件でも在るか。命題の原子がこの問いに落ちる。
    pub fn 関係が在るか(&self, 主語: &設計概念の識別子, 種類: 設計関係の種類, 目的語: &設計概念の識別子) -> bool {
        self.関係一覧.iter().any(|関係| &関係.主語 == 主語 && 関係.種類 == 種類 && &関係.目的語 == 目的語)
    }

    /// 主語と種類を固定したときの目的語の一覧。
    pub fn 目的語一覧(&self, 主語: &設計概念の識別子, 種類: 設計関係の種類) -> Vec<&設計概念の識別子> {
        self.関係一覧.iter().filter(|関係| &関係.主語 == 主語 && 関係.種類 == 種類).map(|関係| &関係.目的語).collect()
    }

    /// 種類と目的語を固定したときの主語の一覧。
    pub fn 主語一覧(&self, 種類: 設計関係の種類, 目的語: &設計概念の識別子) -> Vec<&設計概念の識別子> {
        self.関係一覧.iter().filter(|関係| 関係.種類 == 種類 && &関係.目的語 == 目的語).map(|関係| &関係.主語).collect()
    }

    /// その関係の種類の辺だけを辿って主語から目的語へ達する経路が在るか。幅優先で辿り、同じ節点を2度は辿らない。
    /// グラフの検証器が「AからBへ依存の経路が存在しない」を問うために要る。
    pub fn 経路が在るか(&self, 主語: &設計概念の識別子, 種類の集合: &[設計関係の種類], 目的語: &設計概念の識別子) -> bool {
        let mut 済み = HashSet::new();
        let mut 待ち = vec![主語.clone()];
        済み.insert(主語.clone());
        while let Some(いま) = 待ち.pop() {
            for 種類 in 種類の集合 {
                for 次 in self.目的語一覧(&いま, *種類) {
                    if 次 == 目的語 {
                        return true;
                    }
                    if 済み.insert(次.clone()) {
                        待ち.push(次.clone());
                    }
                }
            }
        }
        false
    }

    /// その概念が、主語としても目的語としても1つも関係に参加していないか。設計の受理の命題がこの問いを読む。
    pub fn 関係へ1つも参加していないか(&self, 概念: &設計概念の識別子) -> bool {
        !self.関係一覧.iter().any(|関係| &関係.主語 == 概念 || &関係.目的語 == 概念)
    }
}
