//! 設計関係とは、2つの設計概念の間に成り立つ、設計上の意味を持つ結び付きのことである。
//! 設計の関係の語彙は5語であり、エンティティとその目印の型のつながりの1語(`識別する`)と、関数の引数と戻り値の役目の4語から成る。
//! 役目の4語は、データの流れの3語(`変換用の素材にする`・`生成する`・`参照する`)と、規則によらない書き換えの1語(`書き換える`)である。
//! この5語は最終語彙として固定したものではなく、実際の設計を記述・検査できるかを確かめるための最小の集合である。
//! `書き換える` を `変換用の素材にする` と `生成する` の組で表さないのは、同じ処理が状態を変換用の素材にしかつ生成することが状態の存在理由の公理(規則で進むこと)の条件であり、
//! 規則によらない書き換えをその組で表すと、規則で進まない状態が公理を通るためである(`_doc/設計/設計オントロジー.md` 6.5節・第8節)。
//!
//! **`保持する` をこの語彙に入れない。** フィールドに持つことはコードの形であり、プリミティブの高さの関係である(Issue #193「関係には3つの高さがある」)。
//! 設計の関係と同じ種類の辺として並べると、原子命題 `設計関係が在る` がコードの形まで問うことになるため、`プリミティブな関係` として別の高さに置く。
//! **マーカーの実装と上位トレイトの宣言もこの語彙に入れない。** 前者は型へ分類を与える宣言であり、後者は分類どうしの公理であって、
//! どちらも2つの概念のあいだの関係ではないためである。この2つは `分類の事実` が持ち、設計関係グラフが節点の分類として閉じて持つ。
//!
//! **設計関係とプリミティブな関係は、プリミティブな事実の上の定義の式から導出する。** 抽出器は事実だけを出し、関係を直接出さない。
//! 生の `fn f(a: A) -> B` から `A を変換用の素材にする`・`B を生成する` を決める規則は置かない。置くと、関数の引数と戻り値という言語の形がそのまま
//! 設計の意味になり、設計として説明可能かを問う力を失う。導出した1件は、使った規則の名前と事実の出どころを `導出の根拠` として持つ。
//! 参照: `_doc/設計/設計オントロジー.md` 第6節、Issue #193「定義の式」。

