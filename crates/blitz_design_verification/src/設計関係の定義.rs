mod プリミティブな関係の定義;
#[path = "設計関係の定義/導出の根拠の定義.rs"]
mod 導出の根拠の定義;
#[path = "設計関係の定義/関数の引数と戻り値の役目の定義.rs"]
mod 関数の引数と戻り値の役目の定義;

pub use プリミティブな関係の定義::{プリミティブな関係, プリミティブな関係の種類};
pub use 導出の根拠の定義::導出の根拠;
pub use 関数の引数と戻り値の役目の定義::関数の引数と戻り値の役目;

/// 設計関係の1件。主語と目的語と結び付き方に加えて、どのソースのどの構文の事実から、どの規則で導いたかを持つ。
/// 出どころと根拠を持つのは、抽出と定義の式が信頼基盤であり、誤ったときに人がその行と規則へ戻れなければ検証の結果を確かめられないためである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 設計関係 {
    /// 関係の主語に立つ設計概念への参照。
    pub 主語: 設計概念への参照,
    /// 識別するか、関数の引数と戻り値の役目のどれか。
    pub 結び付き方: 設計関係の結び付き方,
    /// 関係の目的語に立つ設計概念への参照。
    pub 目的語: 設計概念への参照,
    /// この1件がどのソースのどの行のどの構文から出たか。
    pub 出どころ: 抽出の出どころ,
    /// この1件を導いた規則の名前と、使った事実の出どころ。
    pub 根拠: 導出の根拠,
}

/// 設計関係が何の結び付きであるか。エンティティとその目印の型のつながり(`識別する`)か、関数の役割の宣言の型引数の位置が表す役目かのどちらかである。
/// `識別する` を `関数の引数と戻り値の役目` に入れないのは、関数の引数でも戻り値でもないためである(2026-09-30 オーナー裁定)。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum 設計関係の結び付き方 {
    /// 主語がエンティティである目的語の同一性を担う識別子である。
    識別する,
    /// 主語の処理が目的語を、関数の役割の宣言の型引数の位置が表す役目で受け取るか返す。
    関数の引数と戻り値の役目(関数の引数と戻り値の役目),
}

/// 導いた1件の関係が、どのソースのどの行のどの構文の事実に由来するか。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 抽出の出どころ {
    /// リポジトリからの相対のソースのパス。
    pub パス: PathBuf,
    /// そのソースの中の行番号。1始まりである。
    pub 行番号: usize,
    /// 関係を導く事実がどの構文に書かれていたか。
    pub 構文: 抽出元の構文,
}

/// 関係を導く事実が書かれるRustの構文。この列挙に無い構文の事実から関係を導かない。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum 抽出元の構文 {
    /// `struct 旅行者 { 識別子: 旅行者ID }` から `旅行者 保持する 旅行者ID` を導く。
    構造体のフィールド,
    /// `impl Mエンティティ for 旅行者 { type 識別子 = 旅行者ID; }` から `旅行者ID 識別する 旅行者` を導く。
    エンティティの識別子の関連型,
    /// `M解釈関数<入力, コマンド>` の型引数から `変換用の素材にする`・`生成する`・`参照する`・`書き換える` を導く。
    関数の役割の型引数,
    /// `impl 型 { fn f(&self, a: A) -> B }` の見出しから、プリミティブな関係の `関連関数として持つ`・`引数に取る`・`返す` を導く。設計の関係は導かない。
    関数の署名,
}

impl 設計関係の結び付き方 {
    /// 設計の関係の語彙の全件。検証器の網羅の走査がこの並びを読む。
    pub const fn 最小語彙() -> [Self; 5] {
        let [素材, 生成, 参照, 書き換え] = 関数の引数と戻り値の役目::全部();
        [
            Self::識別する,
            Self::関数の引数と戻り値の役目(素材),
            Self::関数の引数と戻り値の役目(生成),
            Self::関数の引数と戻り値の役目(参照),
            Self::関数の引数と戻り値の役目(書き換え),
        ]
    }

    /// 人が読む語。報告と試験の判定がこの語を使う。
    pub const fn 語(self) -> &'static str {
        match self {
            Self::識別する => "識別する",
            Self::関数の引数と戻り値の役目(役目) => 役目.語(),
        }
    }
}

impl 設計関係 {
    /// 人が読む1行の表記。`旅行者ID 識別する 旅行者` の形である。
    pub fn 表記(&self) -> String {
        format!("{} {} {}", self.主語.表記(), self.結び付き方.語(), self.目的語.表記())
    }
}
