//! 証拠とは、証明済みの根拠のことである。どの検証の方式で示したかと、何件の対象を全部見たかと、人が読む説明を持つ。

use super::検証の方式;

/// 証明済みの根拠。どの方式で、何を全部見たかを持つ。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 証拠 {
    方式: 検証の方式,
    見た対象の件数: usize, // 構造の検証では照合した関係の件数、有限全数では列挙した状態と状態遷移の件数である
    説明: String,          // 「対象の32件の状態遷移を全部列挙した」の形の1行
}

impl 証拠 {
    /// 成立を示した手立てと、全部見た対象の件数と、人が読む1行の説明から組む。
    pub fn 生成する(方式: 検証の方式, 見た対象の件数: usize, 説明: String) -> Self {
        Self { 方式, 見た対象の件数, 説明 }
    }

    /// 成立を示した手立て。
    pub fn 方式(&self) -> 検証の方式 {
        self.方式
    }

    /// 全部見た対象の件数。
    pub fn 見た対象の件数(&self) -> usize {
        self.見た対象の件数
    }

    /// 人が読む1行の説明。
    pub fn 説明(&self) -> &str {
        &self.説明
    }
}
