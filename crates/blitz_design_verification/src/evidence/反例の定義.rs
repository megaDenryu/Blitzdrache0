//! 反例とは、反証済みの根拠のことである。どの検証の方式で見つけたかと、何が期待と違ったかの説明と、人がその状況へ戻るための再現の材料を持つ。

use super::検証の方式;

/// 反証済みの根拠。人が再現できる材料を持つ。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 反例 {
    方式: 検証の方式,
    説明: String,
    再現の材料: Vec<(String, String)>, // 前状態・入力・状態遷移・得られた出来事・期待した出来事のような、名前と値の対
}

impl 反例 {
    /// 反例を見つけた手立てと、何が期待と違ったかを人へ伝える1行と、再現の材料から組む。
    pub fn 生成する(方式: 検証の方式, 説明: String, 再現の材料: Vec<(String, String)>) -> Self {
        Self { 方式, 説明, 再現の材料 }
    }

    /// 反例を見つけた手立て。
    pub fn 方式(&self) -> 検証の方式 {
        self.方式
    }

    /// 何が期待と違ったかを人へ伝える1行。
    pub fn 説明(&self) -> &str {
        &self.説明
    }

    /// 名前と値の対の並び。人がその状況へ戻るために持つ。
    pub fn 再現の材料(&self) -> &[(String, String)] {
        &self.再現の材料
    }
}
