//! 命題とは、設計について真偽を問う式のことである(Issue #173。層3の本体)。
//!
//! 原子・否定・連言・選言・含意(第1段階)と全称・存在(第2段階)を1つの列挙で持つ。段階は実装の順序であって除外ではなく、
//! 量化を後から別の型として足すと、検証器の側も「量化の無い命題」と「量化のある命題」の2つの入口を持つことになる。
//!
//! 命題は真偽の値を持たない。真偽を答えるのは検証器であり、しかも答えは3値(証明済み・反証済み・未決定)である。
//! 参照: `_doc/設計/設計オントロジー.md` 第7節。

mod nonempty;
#[cfg(test)]
mod nonempty_tests;

pub use nonempty::{非空の命題一覧, 非空の命題一覧の生成の失敗};

use super::atom::原子命題;
use super::quantification::{対象集合, 束縛変数};

/// 設計について真偽を問う式。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 命題 {
    /// それ以上分解しない最小の主張。
    原子(原子命題),
    /// 本体が成り立たない。
    否定(Box<命題>),
    /// 並びの全部が成り立つ。積載物が非空であるため、項を1件も見ない連言は表現できない。
    連言(非空の命題一覧),
    /// 並びのいずれか1つが成り立つ。積載物が非空であるため、項を1件も見ない選言は表現できない。
    選言(非空の命題一覧),
    /// 前件が成り立つならば後件も成り立つ。
    含意 {
        /// 成り立つときだけ後件を問う側の命題。
        前件: Box<命題>,
        /// 前件が成り立つときに成り立つべき命題。
        後件: Box<命題>,
    },
    /// 対象集合の全ての要素を束縛へ当てて本体が成り立つ。
    全称 {
        /// 対象集合の要素を当てる変数。本体の中の項がこの変数を指す。
        束縛: 束縛変数,
        /// 束縛へ当てる要素が走る範囲。
        対象集合: 対象集合,
        /// 要素ごとに真偽を問う命題。
        本体: Box<命題>,
    },
    /// 対象集合のいずれか1つの要素を束縛へ当てて本体が成り立つ。
    存在 {
        /// 対象集合の要素を当てる変数。本体の中の項がこの変数を指す。
        束縛: 束縛変数,
        /// 束縛へ当てる要素が走る範囲。
        対象集合: 対象集合,
        /// 要素ごとに真偽を問う命題。
        本体: Box<命題>,
    },
}

impl 命題 {
    /// 原子命題1つを命題へ包む。
    pub fn 原子から組む(原子: 原子命題) -> Self {
        Self::原子(原子)
    }

    /// この命題の否定を組む。
    pub fn 否定する(self) -> Self {
        Self::否定(Box::new(self))
    }

    /// 連言を組む。0件の並びは、要求を1件も見ないまま証明済みになる偽の証明であるため、失敗で拒む。
    pub fn 連言を組む(項一覧: Vec<Self>) -> Result<Self, 非空の命題一覧の生成の失敗> {
        Ok(Self::連言(非空の命題一覧::生成する(項一覧)?))
    }

    /// 選言を組む。0件の並びは恒偽であり、否定の下で何も見ずに証明済みを作るため、失敗で拒む。
    pub fn 選言を組む(項一覧: Vec<Self>) -> Result<Self, 非空の命題一覧の生成の失敗> {
        Ok(Self::選言(非空の命題一覧::生成する(項一覧)?))
    }

    /// 含意を組む。
    pub fn 含意を組む(前件: Self, 後件: Self) -> Self {
        Self::含意 {
            前件: Box::new(前件), 後件: Box::new(後件)
        }
    }

    /// 全称を組む。
    pub fn 全称を組む(束縛: 束縛変数, 対象集合: 対象集合, 本体: Self) -> Self {
        Self::全称 {
            束縛, 対象集合, 本体: Box::new(本体)
        }
    }

    /// 存在を組む。
    pub fn 存在を組む(束縛: 束縛変数, 対象集合: 対象集合, 本体: Self) -> Self {
        Self::存在 {
            束縛, 対象集合, 本体: Box::new(本体)
        }
    }

    /// 人が読む1行の表記。命題の集合の報告と反例の説明がこの表記を使う。
    pub fn 表記(&self) -> String {
        match self {
            Self::原子(原子) => 原子.表記(),
            Self::否定(本体) => format!("NOT ({})", 本体.表記()),
            Self::連言(項一覧) => Self::並びを綴る(項一覧.一覧(), " AND "),
            Self::選言(項一覧) => Self::並びを綴る(項一覧.一覧(), " OR "),
            Self::含意 { 前件, 後件 } => format!("({}) ならば ({})", 前件.表記(), 後件.表記()),
            Self::全称 { 束縛, 対象集合, 本体 } => {
                format!("全ての?{}が{}について ({})", 束縛.名前(), 対象集合.表記(), 本体.表記())
            }
            Self::存在 { 束縛, 対象集合, 本体 } => {
                format!("ある?{}が{}について ({})", 束縛.名前(), 対象集合.表記(), 本体.表記())
            }
        }
    }

    /// 連言と選言の並びを、区切りの語で繋いだ1行へ綴る。
    fn 並びを綴る(項一覧: &[Self], 区切り: &str) -> String {
        let 綴り一覧: Vec<String> = 項一覧.iter().map(|項| format!("({})", 項.表記())).collect();
        綴り一覧.join(区切り)
    }
}
