#[cfg(test)]
mod nonempty_tests;
#[path = "proposition/全称命題の定義.rs"]
mod 全称命題の定義;
#[path = "proposition/含意命題の定義.rs"]
mod 含意命題の定義;
#[path = "proposition/存在命題の定義.rs"]
mod 存在命題の定義;

pub use nonempty::{非空の命題一覧, 非空の命題一覧の生成の失敗};
pub use 全称命題の定義::全称命題;
pub use 含意命題の定義::含意命題;
pub use 存在命題の定義::存在命題;

use super::原子命題の定義::原子命題;
use super::量化の語彙::{束縛変数, 量化の対象集合};

/// 設計について真偽を問う式。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 命題 {
    /// それ以上分解しない最小の主張。原子命題は項を3つまで持って他の選択肢より大きく、列挙全体を膨らませないため箱に入れる。
    原子(Box<原子命題>),
    /// 本体が成り立たない。
    否定(Box<命題>),
    /// 並びの全部が成り立つ。積載物が非空であるため、項を1件も見ない連言は表現できない。
    連言(非空の命題一覧),
    /// 並びのいずれか1つが成り立つ。積載物が非空であるため、項を1件も見ない選言は表現できない。
    選言(非空の命題一覧),
    /// 前件が成り立つならば後件も成り立つ。
    含意(含意命題),
    /// 量化の対象集合の全ての要素を束縛へ当てて本体が成り立つ。
    全称(全称命題),
    /// 量化の対象集合のいずれか1つの要素を束縛へ当てて本体が成り立つ。
    存在(存在命題),
}

impl 命題 {
    /// 原子命題1つを命題へ包む。
    pub fn 原子から組む(原子: 原子命題) -> Self {
        Self::原子(Box::new(原子))
    }

    /// この命題の否定を組む。
    pub fn 否定する(self) -> Self {
        Self::否定(Box::new(self))
    }

    /// 連言を組む。0件の並びは、要求を1件も見ないまま証明済みになる偽の証明であるため、失敗で拒む。
    pub fn 連言を組む(項一覧: Vec<Self>) -> Result<Self, 非空の命題一覧の生成の失敗> {
        Ok(Self::連言(非空の命題一覧::生成する(項一覧)?))
    }

    /// 選言を組む。0件の並びは恒偽であり、否定の下で何も見ずに証明済みを作るため、失敗で拒む。
    pub fn 選言を組む(項一覧: Vec<Self>) -> Result<Self, 非空の命題一覧の生成の失敗> {
        Ok(Self::選言(非空の命題一覧::生成する(項一覧)?))
    }

    /// 含意を組む。
    pub fn 含意を組む(前件: Self, 後件: Self) -> Self {
        Self::含意(含意命題::生成する(前件, 後件))
    }

    /// 全称を組む。
    pub fn 全称を組む(束縛: 束縛変数, 量化の対象集合: 量化の対象集合, 本体: Self) -> Self {
        Self::全称(全称命題::生成する(束縛, 量化の対象集合, 本体))
    }

    /// 存在を組む。
    pub fn 存在を組む(束縛: 束縛変数, 量化の対象集合: 量化の対象集合, 本体: Self) -> Self {
        Self::存在(存在命題::生成する(束縛, 量化の対象集合, 本体))
    }

    /// 人が読む1行の表記。命題の集合の報告と反例の説明がこの表記を使う。
    pub fn 表記(&self) -> String {
        match self {
            Self::原子(原子) => 原子.表記(),
            Self::否定(本体) => format!("NOT ({})", 本体.表記()),
            Self::連言(項一覧) => Self::並びを綴る(項一覧.一覧(), " AND "),
            Self::選言(項一覧) => Self::並びを綴る(項一覧.一覧(), " OR "),
            Self::含意(含意) => 含意.表記(),
            Self::全称(全称) => 全称.表記(),
            Self::存在(存在) => 存在.表記(),
        }
    }

    /// 連言と選言の並びを、区切りの語で繋いだ1行へ綴る。
    fn 並びを綴る(項一覧: &[Self], 区切り: &str) -> String {
        let 文字列一覧: Vec<String> = 項一覧.iter().map(|項| format!("({})", 項.表記())).collect();
        文字列一覧.join(区切り)
    }
}
