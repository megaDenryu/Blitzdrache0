//! 排他の推論規則が、一方のイベントの発生の成立から他方の不発生を導くことを固定する試験。
//!
//! 前提の `発生する` は構造の検証器では解けないため、試験の中の差し替え可能な検証器が証明済みを返す形で組む。

#![allow(clippy::unwrap_used)]

use crate::設計概念への参照;

use super::atom::{原子命題, 項};
use super::evidence::{未決定の理由, 検証の方式, 検証結果, 証拠};
use super::law::{排他の推論規則, 推論規則};
use super::proposition::{命題, 非空の命題一覧};
use super::quantification::{対象集合, 束縛変数};
use super::verifier::命題の検証器;

/// 渡された命題を無条件に証明済みで答える検証器。前提が成立している状況だけを作るために置く。
struct 常に証明済みで答える検証器;

impl 命題の検証器 for 常に証明済みで答える検証器 {
    fn 検証する(&self, _命題: &命題) -> 検証結果 {
        検証結果::証明済み(証拠 {
            方式: 検証の方式::有限全数,
            見た対象の件数: 1,
            説明: "試験の検証器が成立を答えた".to_string(),
        })
    }
}

fn イベント(名前: &str) -> 設計概念への参照 {
    設計概念への参照::型として生成する("blitz_esca::event", 名前)
}

/// 「到達可能な全ての遷移について、前件が成り立つならば到達した事象が発生する」という全称の含意。
fn 到達した事象が発生する全称(束縛: &束縛変数) -> 命題 {
    命題::全称を組む(
        束縛.clone(),
        対象集合::到達可能な遷移,
        命題::含意を組む(
            命題::原子から組む(原子命題::到達可能である { 状態: 項::束縛変数(束縛.clone()) }),
            命題::原子から組む(原子命題::発生する {
                遷移: 項::束縛変数(束縛.clone()),
                イベント: 項::名指した概念(イベント("到達した")),
            }),
        ),
    )
}

#[test]
fn 排他の推論規則は後件を他方の不発生へ置き換えた命題を導く() {
    let 束縛 = 束縛変数::生成する("t");
    let 規則 = 排他の推論規則::生成する(イベント("到達した"), イベント("通常の事象"));
    let 導いた命題 = 規則
        .発生の否定へ置き換えた命題を導く(&到達した事象が発生する全称(&束縛))
        .unwrap_or_else(|| panic!("後件が発生する(?t, 到達した)である全称の含意から導けなければならない"));
    let 期待する後件 = 規則.他方の不発生を組む(&項::束縛変数(束縛));
    let 命題::全称 { 本体, .. } = &導いた命題 else {
        panic!("導いた命題は全称でなければならない");
    };
    let 命題::含意 { 後件, .. } = 本体.as_ref() else {
        panic!("導いた全称の本体は含意でなければならない");
    };
    assert_eq!(後件.as_ref(), &期待する後件);
}

#[test]
fn 前提が成立しない推論規則は反証済みでなく未決定で答える() {
    let 束縛 = 束縛変数::生成する("t");
    let 規則 = 排他の推論規則::生成する(イベント("到達した"), イベント("通常の事象"));
    let 成立した命題 = 到達した事象が発生する全称(&束縛);
    let 推論 = 規則.推論規則へ写す(&成立した命題).unwrap_or_else(|| panic!("推論規則へ写せなければならない"));
    assert!(推論.前提から結論を導く(&常に証明済みで答える検証器).証明済みか());
    let 前提が成立しない規則 = 推論規則::生成する("前提が立たない規則", 非空の命題一覧::先頭と残りから生成する(成立した命題, Vec::new()), 推論.結論().clone());
    let 結末 = 前提が成立しない規則.前提から結論を導く(&常に未決定で答える検証器);
    assert!(matches!(結末, 検証結果::未決定(未決定の理由::推論規則の前提を証明できない(_))));
}

/// 渡された命題を無条件に未決定で答える検証器。前提が成立しない状況を作るために置く。
struct 常に未決定で答える検証器;

impl 命題の検証器 for 常に未決定で答える検証器 {
    fn 検証する(&self, _命題: &命題) -> 検証結果 {
        検証結果::未決定(未決定の理由::この検証器が扱わない式を含む("試験の検証器".to_string()))
    }
}
