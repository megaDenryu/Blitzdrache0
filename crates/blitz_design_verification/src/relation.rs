//! 設計関係とは、2つの設計概念の間に成り立つ、設計上の意味を持つ結び付きのことである。
//! 第1実験の最小語彙は6語であり、構造の3語(`下位型である`・`保持する`・`識別する`)とデータの流れの3語(`消費する`・`生成する`・`参照する`)から成る。
//! この6語は最終語彙として固定したものではなく、実際の設計を記述・検査できるかを確かめるための最小の集合である。
//!
//! **抽出は構文と設計解釈マーカーと関数の役割の組からのみ行う。** 生の `fn f(a: A) -> B` から `A を消費する`・`B を生成する` を決めることはしない。
//! 決めてしまうと、関数の引数と戻り値という言語の形がそのまま設計の意味になり、設計として説明可能かを問う力を失う。
//! 抽出元の対応は `抽出元の構文` の各選択肢が答え、全文は `_doc/設計/設計オントロジー.md` 第6節の表が持つ。
//! 参照: `_doc/設計/設計オントロジー.md` 第6節。

use std::path::PathBuf;

use super::concept::設計概念の識別子;

/// 設計関係の1件。主語と目的語と種類に加えて、どのソースのどの構文から抽出したかを持つ。
/// 出どころを持つのは、抽出器が信頼基盤であり、抽出が誤ったときに人がその行へ戻れなければ検証の結果を確かめられないためである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 設計関係 {
    pub 主語: 設計概念の識別子,
    pub 種類: 設計関係の種類,
    pub 目的語: 設計概念の識別子,
    pub 出どころ: 抽出の出どころ,
}

/// 第1実験の最小語彙6語。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum 設計関係の種類 {
    下位型である,
    保持する,
    識別する,
    消費する,
    生成する,
    参照する,
}

/// 抽出した1件が、どのソースのどの行のどの構文から出たか。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 抽出の出どころ {
    pub パス: PathBuf,
    pub 行番号: usize, // 1始まり
    pub 構文: 抽出元の構文,
}

/// 設計関係を抽出してよいRustの構文。この列挙に無い構文から関係を抽出しない。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum 抽出元の構文 {
    上位トレイトの宣言,           // `trait M状態: M不変データ {}` から `M状態 下位型である M不変データ`
    設計解釈マーカーの実装,       // `impl M状態 for 旅行者` から `旅行者 下位型である M状態`
    構造体のフィールド,           // `struct 旅行者 { 識別子: 旅行者ID }` から `旅行者 保持する 旅行者ID`
    エンティティの識別子の関連型, // `impl Mエンティティ for 旅行者 { type 識別子 = 旅行者ID; }` から `旅行者ID 識別する 旅行者`
    関数の役割の型引数,           // `M解釈関数<入力, コマンド>` の型引数から `消費する`・`生成する`・`参照する`
}

impl 設計関係の種類 {
    /// 第1実験の最小語彙の全件。検証器の網羅の走査がこの並びを読む。
    pub const fn 最小語彙() -> [Self; 6] {
        [Self::下位型である, Self::保持する, Self::識別する, Self::消費する, Self::生成する, Self::参照する]
    }

    /// 人が読む語。報告と試験の判定がこの語を使う。
    pub const fn 語(self) -> &'static str {
        match self {
            Self::下位型である => "下位型である",
            Self::保持する => "保持する",
            Self::識別する => "識別する",
            Self::消費する => "消費する",
            Self::生成する => "生成する",
            Self::参照する => "参照する",
        }
    }
}

impl 設計関係 {
    /// 人が読む1行の表記。`旅行者ID 識別する 旅行者` の形である。
    pub fn 表記(&self) -> String {
        format!("{} {} {}", self.主語.表記(), self.種類.語(), self.目的語.表記())
    }
}
