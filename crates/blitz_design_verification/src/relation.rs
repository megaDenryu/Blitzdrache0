//! 設計関係とは、2つの設計概念の間に成り立つ、設計上の意味を持つ結び付きのことである。
//! 設計の関係の語彙は4語であり、構造の1語(`識別する`)とデータの流れの3語(`消費する`・`生成する`・`参照する`)から成る。
//! この4語は最終語彙として固定したものではなく、実際の設計を記述・検査できるかを確かめるための最小の集合である。
//!
//! **`保持する` をこの語彙に入れない。** フィールドに持つことはコードの形であり、プリミティブの高さの関係である(Issue #193「関係には3つの高さがある」)。
//! 設計の関係と同じ種類の辺として並べると、原子命題 `設計関係が在る` がコードの形まで問うことになるため、`保持する関係` として別の高さに置く。
//! **マーカーの実装と上位トレイトの宣言もこの語彙に入れない。** 前者は型へ分類を与える宣言であり、後者は分類どうしの公理であって、
//! どちらも2つの概念のあいだの関係ではないためである。この2つは `分類の事実` が持ち、設計関係グラフが節点の分類として閉じて持つ。
//!
//! **設計関係と保持する関係は、プリミティブな事実の上の定義の式から導出する。** 抽出器は事実だけを出し、関係を直接出さない。
//! 生の `fn f(a: A) -> B` から `A を消費する`・`B を生成する` を決める規則は置かない。置くと、関数の引数と戻り値という言語の形がそのまま
//! 設計の意味になり、設計として説明可能かを問う力を失う。導出した1件は、使った規則の名前と事実の出どころを `導出の根拠` として持つ。
//! 参照: `_doc/設計/設計オントロジー.md` 第6節、Issue #193「定義の式」。

use std::path::PathBuf;

use super::concept::設計概念への参照;

#[path = "relation/保持する関係の定義.rs"]
mod 保持する関係の定義;
#[path = "relation/導出の根拠の定義.rs"]
mod 導出の根拠の定義;

pub use 保持する関係の定義::保持する関係;
pub use 導出の根拠の定義::導出の根拠;

/// 設計関係の1件。主語と目的語と種類に加えて、どのソースのどの構文の事実から、どの規則で導いたかを持つ。
/// 出どころと根拠を持つのは、抽出と定義の式が信頼基盤であり、誤ったときに人がその行と規則へ戻れなければ検証の結果を確かめられないためである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 設計関係 {
    /// 関係の主語に立つ設計概念への参照。
    pub 主語: 設計概念への参照,
    /// 設計の関係の4語のどれであるか。
    pub 種類: 設計関係の種類,
    /// 関係の目的語に立つ設計概念への参照。
    pub 目的語: 設計概念への参照,
    /// この1件がどのソースのどの行のどの構文から出たか。
    pub 出どころ: 抽出の出どころ,
    /// この1件を導いた規則の名前と、使った事実の出どころ。
    pub 根拠: 導出の根拠,
}

/// 設計の関係の語彙4語。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum 設計関係の種類 {
    /// 主語がエンティティである目的語の同一性を担う識別子である。
    識別する,
    /// 主語の処理が目的語を入力として受け取る。
    消費する,
    /// 主語の処理が目的語を出力として作る。
    生成する,
    /// 主語の処理が目的語を読み取り専用で読む。
    参照する,
}

/// 導いた1件の関係が、どのソースのどの行のどの構文の事実に由来するか。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 抽出の出どころ {
    /// リポジトリからの相対のソースのパス。
    pub パス: PathBuf,
    /// そのソースの中の行番号。1始まりである。
    pub 行番号: usize,
    /// 関係を導く事実がどの構文に書かれていたか。
    pub 構文: 抽出元の構文,
}

/// 関係を導く事実が書かれるRustの構文。この列挙に無い構文の事実から関係を導かない。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum 抽出元の構文 {
    /// `struct 旅行者 { 識別子: 旅行者ID }` から `旅行者 保持する 旅行者ID` を導く。
    構造体のフィールド,
    /// `impl Mエンティティ for 旅行者 { type 識別子 = 旅行者ID; }` から `旅行者ID 識別する 旅行者` を導く。
    エンティティの識別子の関連型,
    /// `M解釈関数<入力, コマンド>` の型引数から `消費する`・`生成する`・`参照する` を導く。
    関数の役割の型引数,
    /// 役割の定義が固定で取る入力から関係を導く。`M遷移関数` の `遷移パラメータ` がこれであり、表記は使用箇所の行でなく役割の定義の側に在る。
    関数の役割が固定で持つ入力,
}

impl 設計関係の種類 {
    /// 設計の関係の語彙の全件。検証器の網羅の走査がこの並びを読む。
    pub const fn 最小語彙() -> [Self; 4] {
        [Self::識別する, Self::消費する, Self::生成する, Self::参照する]
    }

    /// 人が読む語。報告と試験の判定がこの語を使う。
    pub const fn 語(self) -> &'static str {
        match self {
            Self::識別する => "識別する",
            Self::消費する => "消費する",
            Self::生成する => "生成する",
            Self::参照する => "参照する",
        }
    }
}

impl 設計関係 {
    /// 人が読む1行の表記。`旅行者ID 識別する 旅行者` の形である。
    pub fn 表記(&self) -> String {
        format!("{} {} {}", self.主語.表記(), self.種類.語(), self.目的語.表記())
    }
}
