//! プリミティブな関係とは、コードの形について語る関係のことである(Issue #193「関係には3つの高さがある」)。
//! 型が別の型をフィールドとして持つこと(保持する)がこれに当たる。種類を欄として持ち、関係の語を足すたびに型や原子命題の選択肢を増やさない。
//!
//! 設計関係(設計の高さ)と別の型にするのは、プリミティブな関係がコードの形であって設計の役割ではないためである。
//! 同じ型にすると、原子命題 `設計関係が在る` と対象集合 `全ての設計関係の主語` がコードの形まで拾い、設計の関係だけを問えなくなる。
//! プリミティブな関係を問う原子命題は `プリミティブな関係が在る` と `プリミティブな関係の経路が在る` であり、設計の関係を問う原子と別に置く。
//! 設計関係への参加の問い(`設計関係グラフ::設計関係へ1つも参加していないか`)はプリミティブな関係を数えない。設計の意味を持たないためである(Issue #193 の段階3)。

use super::{導出の根拠, 抽出の出どころ};
use crate::設計概念への参照;

/// プリミティブな関係の1件。主語から目的語へ、その種類のコードの形の結び付きが在る。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct プリミティブな関係 {
    /// 関係の主語に立つ設計概念への参照。
    pub 主語: 設計概念への参照,
    /// プリミティブな関係のどの語であるか。
    pub 種類: プリミティブな関係の種類,
    /// 関係の目的語に立つ設計概念への参照。
    pub 目的語: 設計概念への参照,
    /// この1件がどのソースのどの行のどの構文の事実に由来するか。
    pub 出どころ: 抽出の出どころ,
    /// この1件を導いた規則の名前と、使った事実の出どころ。
    pub 根拠: 導出の根拠,
}

/// プリミティブな関係の語彙。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum プリミティブな関係の種類 {
    /// 主語の型が目的語の型をフィールドとして持つ。
    保持する,
}

impl プリミティブな関係の種類 {
    /// プリミティブな関係の語彙の全件。欠落が弱める答えの全件と報告の内訳がこの並びを読む。
    pub const fn 全部() -> [Self; 1] {
        [Self::保持する]
    }

    /// 人が読む語。報告と試験の判定がこの語を使う。
    pub const fn 語(self) -> &'static str {
        match self {
            Self::保持する => "保持する",
        }
    }
}

impl プリミティブな関係 {
    /// 人が読む1行の表記。`旅行者 保持する 旅行者ID` の形である。
    pub fn 表記(&self) -> String {
        format!("{} {} {}", self.主語.表記(), self.種類.語(), self.目的語.表記())
    }
}
