//! 保持する関係とは、型が別の型をフィールドとして持つという、プリミティブの高さの関係のことである(Issue #193「関係には3つの高さがある」)。
//!
//! 設計関係(設計の高さ)と別の型にするのは、「フィールドに持つ」がコードの形であって設計の役割ではないためである。
//! 同じ型にすると、原子命題 `設計関係が在る` と対象集合 `全ての設計関係の主語` がコードの形まで拾い、設計の関係だけを問えなくなる。
//! 保持するを問う原子命題は `保持する関係が在る` と `保持する関係の経路が在る` であり、設計の関係を問う原子と別に置く。
//! 設計関係への参加の問い(`設計関係グラフ::設計関係へ1つも参加していないか`)は保持するを数えない。保持するは設計の意味を持たないためである(Issue #193 の段階3)。

use super::{導出の根拠, 抽出の出どころ};
use crate::設計概念への参照;

/// 保持する関係の1件。主語が目的語をフィールドとして持つ。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 保持する関係 {
    /// フィールドを持つ型への参照。
    pub 主語: 設計概念への参照,
    /// フィールドの型が名指す型への参照。
    pub 目的語: 設計概念への参照,
    /// この1件がどのソースのどの行のどの構文の事実に由来するか。
    pub 出どころ: 抽出の出どころ,
    /// この1件を導いた規則の名前と、使った事実の出どころ。
    pub 根拠: 導出の根拠,
}

impl 保持する関係 {
    /// 人が読む語。報告と試験の判定がこの語を使う。
    pub const fn 語() -> &'static str {
        "保持する"
    }

    /// 人が読む1行の表記。`旅行者 保持する 旅行者ID` の形である。
    pub fn 表記(&self) -> String {
        format!("{} {} {}", self.主語.表記(), Self::語(), self.目的語.表記())
    }
}
