//! 導出の根拠とは、導出した1件の関係について、それを導いた定義の式の規則の名前と、規則の本体が使ったプリミティブな事実の出どころを並べたもののことである。
//!
//! この値が在るのは、報告が「この関係はどの規則が、どの行の事実から導いたか」を示せるようにするためである(Issue #193「定義の式」)。
//! 規則を名前で持つのは、規則の値そのものを関係へ複製せずに、`定義の式` の一覧の中の1件へ人が戻れるようにするためである。

use crate::事実の出どころ;

/// 導出した1件の関係の根拠。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 導出の根拠 {
    /// 関係を導いた規則の名前。
    pub 規則の名前: &'static str,
    /// 規則の本体が使った事実の出どころを、使った順に並べた一覧。
    pub 使った事実の出どころ一覧: Vec<事実の出どころ>,
}

impl 導出の根拠 {
    /// 規則の名前と、使った事実の出どころの一覧から組む。定義の式を通さずに関係を直に置く試験は、その旨を規則の名前に書く。
    pub fn 生成する(規則の名前: &'static str, 使った事実の出どころ一覧: Vec<事実の出どころ>) -> Self {
        Self {
            規則の名前, 使った事実の出どころ一覧
        }
    }

    /// 人が読む1行の表記。`規則「…」が a.rs:3 の事実から導いた` の形である。
    pub fn 表記(&self) -> String {
        let 出どころ一覧: Vec<String> = self.使った事実の出どころ一覧.iter().map(|出どころ| format!("{}:{}", 出どころ.パス.display(), 出どころ.行番号)).collect();
        format!("規則「{}」が {} の事実から導いた", self.規則の名前, 出どころ一覧.join("・"))
    }
}
