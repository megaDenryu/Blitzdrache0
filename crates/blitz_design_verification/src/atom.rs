//! 項と原子命題(Issue #173。層3のうち、それ以上分解しない最小の主張)。
//!
//! **4つの設計関係の語を原子命題の選択肢へ展開しない。** `設計関係が在る` が種類を欄として持つ1つの選択肢で足り、
//! 展開すると関係の語を1つ足すたびに原子命題の選択肢と検証器の場合分けが1つずつ増える。
//!
//! **`設計関係が在る` と `設計関係の経路が在る` は別の問いである。** 前者はそのソースがその関係を直接宣言しているかを問い、
//! 後者はその関係が宣言の連なりで推移的に成り立つかを問う。「この型はこの型を間接に保持するか」のように連なりで成り立つ問いは後者でしか成り立たず、
//! 逆に「この処理はこの型を直に消費するか」のような宣言の事実を問う法則は前者しか使えない。法則ごとに書き手がどちらかを選ぶ。
//!
//! **`保持する` を問う原子は設計関係の原子と別に置く。** 保持するはプリミティブの高さの関係であり(Issue #193)、`設計関係が在る` は設計の関係だけを問う。
//! 保持するにも直接の辺を問う `保持する関係が在る` と、辿る経路を問う `保持する関係の経路が在る` の2つが在る。
//!
//! **`マーカーを持つ` は辺でなく分類を問う。** 分類はマーカーの実装を上位トレイトの宣言で閉じたものであり(`節点の分類`)、
//! `M状態` を実装した型について `M不変データ` を持つかを問えば、直接の実装が無くても成り立つ。
//! 定義域は型の主語と設計解釈マーカーの名前である。トレイト・処理の主語や、`Clone` のような設計解釈マーカーでない名前を問うと、
//! 検証器は偽でなく未決定(問いの定義域の外である)で答える。
//!
//! 後ろの3つ(`発生する`・`遷移する`・`到達可能である`)は振る舞いの原子命題であり、構造の検証器はこれを解かない。
//! 構造の検証器は偽で答えず `検証結果::未決定` で答える。解くのは `exhaustive` の有限全数の検証器である。
//! 参照: `_doc/設計/設計オントロジー.md` 第7節・第10節。

use crate::{設計概念への参照, 設計関係の種類};

use super::quantification::{束縛の割り当て, 束縛変数};

/// 原子命題が主語と目的語に取るもの。名指した概念そのままか、量化が当てる束縛変数である。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 項 {
    /// 設計概念を直に名指した項。
    名指した概念(設計概念への参照),
    /// 量化が要素を当てる束縛変数の項。
    束縛変数(束縛変数),
}

/// それ以上分解しない最小の主張。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 原子命題 {
    /// 主語から目的語へその種類の設計関係が1件でも在る。
    設計関係が在る {
        /// 関係の出どころになる概念。
        主語: 項,
        /// 問う関係の語。設計の関係の4語のどれか1つである。
        種類: 設計関係の種類,
        /// 関係の行き先になる概念。
        目的語: 項,
    },
    /// 主語から目的語へ、その種類の辺だけを辿って達する経路が在る。直接の辺1本も経路の1つとして数える。
    設計関係の経路が在る {
        /// 経路の出どころになる概念。
        主語: 項,
        /// 辿ってよい関係の語。この種類の辺だけを辿る。
        種類: 設計関係の種類,
        /// 経路の行き先になる概念。
        目的語: 項,
    },
    /// 主語が目的語をフィールドとして持つ保持する関係が1件でも在る。プリミティブの高さの関係を問う。
    保持する関係が在る {
        /// フィールドを持つ概念。
        主語: 項,
        /// フィールドの型が名指す概念。
        目的語: 項,
    },
    /// 主語から目的語へ、保持する関係の辺だけを辿って達する経路が在る。直接の辺1本も経路の1つとして数える。
    保持する関係の経路が在る {
        /// 経路の出どころになる概念。
        主語: 項,
        /// 経路の行き先になる概念。
        目的語: 項,
    },
    /// その型の分類(実装した設計解釈マーカーを上位トレイトの宣言で閉じたもの)が、その名前の設計解釈マーカーを含む。
    マーカーを持つ {
        /// 実装の有無を問う対象の概念。
        概念: 項,
        /// 実装の有無を問う設計解釈マーカーの名前。正本のトレイトの名前をそのまま書く。
        マーカー名: String,
    },
    /// その概念が主語としても目的語としても、設計関係に1件も参加していない。保持する関係と分類は参加に数えない。
    設計関係へ1つも参加していない {
        /// 孤立しているかを問う対象の概念。
        概念: 項,
    },
    /// その遷移でそのイベントが成立する。振る舞いの原子命題である。
    発生する {
        /// 出来事が成立したかを問う1件の遷移。
        遷移: 項,
        /// その遷移で成立したかを問う出来事。
        イベント: 項,
    },
    /// 前状態へその入力を与えると後状態へ移る。振る舞いの原子命題である。
    遷移する {
        /// 入力を与える前の状態。
        前状態: 項,
        /// 前状態へ与えるコマンド。
        入力: 項,
        /// 入力を与えた後に移るはずの状態。
        後状態: 項,
    },
    /// その状態が初期状態から到達できる。振る舞いの原子命題である。
    到達可能である {
        /// 初期状態から辿り着けるかを問う状態。
        状態: 項,
    },
}

impl 項 {
    /// 束縛の割り当てを読んでこの項が指す設計概念への参照を求める。当てられていない束縛変数では値なしを返す。
    pub fn 束縛の割り当てから設計概念への参照を求める(&self, 割り当て: &束縛の割り当て) -> Option<設計概念への参照> {
        match self {
            Self::名指した概念(参照) => Some(参照.clone()),
            Self::束縛変数(束縛) => 割り当て.束縛変数に当たる概念を求める(束縛).cloned(),
        }
    }

    /// 人が読む1行の表記。束縛変数は名前の前に `?` を付けて名指した概念と見分ける。
    pub fn 表記(&self) -> String {
        match self {
            Self::名指した概念(参照) => 参照.表記(),
            Self::束縛変数(束縛) => format!("?{}", 束縛.名前()),
        }
    }
}

impl 原子命題 {
    /// この原子命題が振る舞いの原子命題(構造の検証器が解かないもの)であるか。
    pub const fn 振る舞いの原子命題か(&self) -> bool {
        matches!(self, Self::発生する { .. } | Self::遷移する { .. } | Self::到達可能である { .. })
    }

    /// 人が読む1行の表記。
    pub fn 表記(&self) -> String {
        match self {
            Self::設計関係が在る { 主語, 種類, 目的語 } => {
                format!("{} {} {}", 主語.表記(), 種類.語(), 目的語.表記())
            }
            Self::設計関係の経路が在る { 主語, 種類, 目的語 } => {
                format!("{}から{}の辺を辿って{}へ達する経路が在る", 主語.表記(), 種類.語(), 目的語.表記())
            }
            Self::保持する関係が在る { 主語, 目的語 } => format!("{} 保持する {}", 主語.表記(), 目的語.表記()),
            Self::保持する関係の経路が在る { 主語, 目的語 } => format!("{}から保持するの辺を辿って{}へ達する経路が在る", 主語.表記(), 目的語.表記()),
            Self::マーカーを持つ { 概念, マーカー名 } => format!("{}は{マーカー名}を持つ", 概念.表記()),
            Self::設計関係へ1つも参加していない { 概念 } => {
                format!("{}は設計関係へ1つも参加していない", 概念.表記())
            }
            Self::発生する { 遷移, イベント } => format!("{}で{}が発生する", 遷移.表記(), イベント.表記()),
            Self::遷移する { 前状態, 入力, 後状態 } => {
                format!("{}へ{}を与えると{}へ遷移する", 前状態.表記(), 入力.表記(), 後状態.表記())
            }
            Self::到達可能である { 状態 } => format!("{}は到達可能である", 状態.表記()),
        }
    }
}
