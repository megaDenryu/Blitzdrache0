//! 設計関係グラフとは、設計概念をノード、設計関係とプリミティブな関係を有向のエッジ、分類をノードのラベルとして持つ、検証の対象になるグラフのことである。
//! 設計関係(設計の高さ)とプリミティブな関係(プリミティブの高さ)を別の一覧として持ち、同じ種類のエッジとして混ぜない(Issue #193)。
//! 分類(マーカーの実装を上位トレイトの宣言で閉じたもの)をエッジにしないのは、それが2つの概念のあいだの関係ではないためである(`各型に付いているマーカーの一覧`)。
//! 命題の検証器はこのグラフへ問いを投げるだけであり、Rustのソースを1度も読み直さない。ソースを読む工程(抽出器)と
//! 問いに答える工程(このグラフ)を分けるのは、抽出が信頼基盤であって検証の正しさと別に回帰試験で固定する対象だからである。
//!
//! **問いの照合は端点の同一性と種類の両方で行う。** エッジの端点も命題の項も `設計概念への参照` であり、その等価は識別子と種類の両方を見る。
//! 識別子だけで照合すると、`トレイト Foo` から張った1本のエッジを「`型 Foo` からそのエッジが在るか」という問いが借りて証明済みを答える。
//! 種類まで照合した結果として、抽出器が目的語の種類を推測して外したエッジは問いから消える。消えたエッジの受け止め方は2つ在り、
//! どちらも反証済みへは落ちない。正しい種類のノードも在るなら `設計関係グラフ::生成する` が同一性の衝突として数え、
//! それが `関係を落とした抽出の欠落` を通って不在に由来する結果を未決定へ倒す。正しい種類のノードが無いなら、
//! 組み立てがノードの無い端点を記録してそのエッジを除き、構造の検証器が不在を根拠にした結果を未決定へ倒す。設計解釈マーカーの宣言の一覧の端点も同じに扱う。
//!
//! 組み立てた設計関係グラフと同一性の衝突をこのファイルが一緒に持つのは、どちらも `設計関係グラフ::生成する` が返すもの以外の何物でもなく、
//! 別ファイルへ移すとデータだけの構造体2つが残って、組み立ての流れを読むのに2ファイルを行き来することになるためである。
//! 参照: `_doc/設計/設計オントロジー.md` 第6節・第7節。

