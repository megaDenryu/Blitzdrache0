/// 抽出済みの設計概念と設計関係の全体。
#[derive(Debug, Clone, Default)]
pub struct 設計関係グラフ {
    ノード: ノードの一覧,
    関係一覧: Vec<設計関係エッジ>,
    プリミティブな関係: プリミティブな関係の一覧,
    ノードが無い端点一覧: Vec<設計概念への参照>,
    各型に付いているマーカーの一覧: 各型に付いているマーカーの一覧,
}

/// 同じ識別子へ種類の違う概念が現れた1件。先に現れた種類と後から現れた種類の両方を持つ。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 同一性の衝突 {
    /// 衝突した識別子。
    pub 識別子: 設計概念の識別子,
    /// 先に現れた方の種類。
    pub 先に現れた種類: 設計概念の種類,
    /// 後から現れた方の種類。
    pub 後から現れた種類: 設計概念の種類,
}

/// グラフを組み立てた結果。組んだグラフと、そのとき見つけた同一性の衝突の一覧の対である。
/// 衝突を返り値へ載せるのは、黙って1ノードへ重複としてまとめたり黙って落としたりせず、呼び出し側に報告させるためである。
#[derive(Debug, Clone, Default)]
pub struct 組み立てた設計関係グラフと同一性の衝突 {
    /// 組み上がったグラフ。
    pub グラフ: 設計関係グラフ,
    /// 組み立ての途中で見つけた同一性の衝突の一覧。
    pub 同一性の衝突一覧: Vec<同一性の衝突>,
}

impl 設計関係グラフ {
    /// 概念と2つの高さの関係の一覧と設計解釈マーカーの宣言の一覧からグラフを組む。同じ識別子で同じ種類の概念は1件にまとめ、種類が違うものは両方をノードとして残して衝突に数える。
    /// 種類が違うものを先勝ちでまとめないのは、検証器のノードの同一性を「先に抽出された方」で決めてはならないためである。
    pub fn 生成する(
        概念一覧: Vec<設計概念ノード>,
        関係一覧: Vec<設計関係エッジ>,
        プリミティブな関係一覧: Vec<プリミティブな関係エッジ>,
        設計解釈マーカーの宣言の一覧: 設計解釈マーカーの宣言の一覧,
    ) -> 組み立てた設計関係グラフと同一性の衝突 {
        let 重複を除いた概念一覧と同一性の衝突 {
            概念一覧: 重複を除いた概念一覧,
            衝突一覧: 同一性の衝突一覧,
        } = 重複を除いた概念一覧と同一性の衝突::概念一覧から生成する(概念一覧);
        let 済みの組: HashSet<_> = 重複を除いた概念一覧.iter().map(|概念| (概念.識別子().clone(), 概念.種類())).collect();
        let ノードが在るか = |端点: &設計概念への参照| 済みの組.contains(&(端点.識別子().clone(), 端点.種類()));
        let (設計解釈マーカーの宣言の一覧, ノードの無い端点を持つ宣言の一覧) = 設計解釈マーカーの宣言の一覧.端点にノードが在るものだけを残す(ノードが在るか);
        let mut 端点の済み = HashSet::new();
        let ノードが無い端点一覧 = 関係一覧
            .iter()
            .flat_map(|関係| [&関係.主語, &関係.目的語])
            .chain(プリミティブな関係一覧.iter().flat_map(|関係| [&関係.主語, &関係.目的語]))
            .chain(ノードの無い端点を持つ宣言の一覧.iter())
            .filter(|端点| !ノードが在るか(端点) && 端点の済み.insert((*端点).clone()))
            .cloned()
            .collect();
        let 関係一覧 = 関係一覧.into_iter().filter(|関係| ノードが在るか(&関係.主語) && ノードが在るか(&関係.目的語)).collect();
        let プリミティブな関係一覧 = プリミティブな関係一覧.into_iter().filter(|関係| ノードが在るか(&関係.主語) && ノードが在るか(&関係.目的語)).collect();
        組み立てた設計関係グラフと同一性の衝突 {
            グラフ: Self {
                ノード: ノードの一覧::生成する(重複を除いた概念一覧),
                関係一覧,
                プリミティブな関係: プリミティブな関係の一覧::生成する(プリミティブな関係一覧),
                ノードが無い端点一覧,
                各型に付いているマーカーの一覧: 各型に付いているマーカーの一覧::設計解釈マーカーの宣言の一覧から閉包を取って生成する(設計解釈マーカーの宣言の一覧),
            },
            同一性の衝突一覧,
        }
    }

    /// 全ての設計概念。
    pub fn 概念一覧(&self) -> &[設計概念ノード] {
        self.ノード.全件()
    }

    /// ノードの一覧と、エッジに触れないノードについての問い(実在・種類での絞り込み・定義をたどれたかだけが違う同じ名前のノード)。
    pub fn ノードを貸す(&self) -> &ノードの一覧 {
        &self.ノード
    }

    /// 全ての設計関係。プリミティブな関係を含まない。
    pub fn 関係一覧(&self) -> &[設計関係エッジ] {
        &self.関係一覧
    }

    /// プリミティブな関係のエッジと、そのエッジについての問い。設計関係の問いはグラフ自身が持ち、プリミティブな関係の問いはこの一覧が持つ。
    pub fn プリミティブな関係を貸す(&self) -> &プリミティブな関係の一覧 {
        &self.プリミティブな関係
    }

    /// ノードごとの分類の索引。分類はエッジではないため、関係への参加の問いはこれを読まない。
    pub fn 各型に付いているマーカーの一覧を貸す(&self) -> &各型に付いているマーカーの一覧 {
        &self.各型に付いているマーカーの一覧
    }

    /// 組み立て時に、識別子と種類が一致するノードを持たなかった端点。関係の端点と設計解釈マーカーの宣言の一覧の端点の両方を含む。
    pub fn ノードが無い端点一覧(&self) -> &[設計概念への参照] {
        &self.ノードが無い端点一覧
    }
}
