//! 排他の推論規則: 2つのイベントが排他であるという法則から、一方の発生の成立から他方の不発生を導く具体の規則。
//!
//! 命題の形を問わずに後件を置き換えず、後件が `発生する(?v, 一方)` である全称の含意だけを受ける。
//! 形を問わないと、排他とは関係の無い命題からこの結論を作れてしまい、導出の正しさが規則の外の規律に依ることになる。

use crate::設計概念への参照;

use super::super::atom::{原子命題, 項};
use super::super::proposition::{命題, 非空の命題一覧};
use super::推論規則;

/// 排他な2つのイベント。
pub struct 排他の推論規則 {
    一方: 設計概念への参照,
    他方: 設計概念への参照,
}

impl 排他の推論規則 {
    /// 排他な2つのイベントへの参照から規則を組む。
    pub fn 生成する(一方: 設計概念への参照, 他方: 設計概念への参照) -> Self {
        Self { 一方, 他方 }
    }

    /// 後件が `発生する(?v, 一方)` である全称の含意の成立から、後件を `NOT 発生する(?v, 他方)` へ置き換えた命題を導く。
    /// 形が合わなければ値なしを返す。
    pub fn 発生の否定へ置き換えた命題を導く(&self, 成立した命題: &命題) -> Option<命題> {
        let 命題::全称 { 束縛, 対象集合, 本体 } = 成立した命題 else {
            return None;
        };
        let 命題::含意 { 前件, 後件 } = 本体.as_ref() else {
            return None;
        };
        let 命題::原子(原子命題::発生する { 遷移, イベント }) = 後件.as_ref() else {
            return None;
        };
        if *遷移 != 項::束縛変数(束縛.clone()) || *イベント != 項::名指した概念(self.一方.clone()) {
            return None;
        }
        Some(命題::全称を組む(束縛.clone(), 対象集合.clone(), 命題::含意を組む(前件.as_ref().clone(), self.他方の不発生を組む(遷移))))
    }

    /// 成立した命題と同じ遷移について、他方のイベントが発生しないという命題を組む。
    pub fn 他方の不発生を組む(&self, 遷移: &項) -> 命題 {
        命題::原子から組む(原子命題::発生する {
            遷移: 遷移.clone(),
            イベント: 項::名指した概念(self.他方.clone()),
        })
        .否定する()
    }

    /// この規則を、成立した命題を前提とし置き換えた命題を結論とする推論規則へ写す。
    /// 形が合わなければ値なしを返す。
    pub fn 推論規則へ写す(&self, 成立した命題: &命題) -> Option<推論規則> {
        let 結論 = self.発生の否定へ置き換えた命題を導く(成立した命題)?;
        let 前提一覧 = 非空の命題一覧::先頭と残りから生成する(成立した命題.clone(), Vec::new());
        Some(推論規則::生成する(&format!("{}と{}は排他である", self.一方.表記(), self.他方.表記()), 前提一覧, 結論))
    }
}
