//! 推論規則が前提から結論を導くときの、前提の件数と証拠の出自と未決定の理由を固定する試験。
//!
//! 見るのは3つである。0件の前提を持つ規則を組めないこと、導いた証拠が `検証の方式::推論` を名乗って前提の方式を説明へ並べること、
//! 前提が反証されたときと確定しなかったときで未決定の理由の説明が読み分けられることである。

#![allow(clippy::unwrap_used)]

use crate::設計概念の識別子;

use super::super::atom::{原子命題, 項};
use super::super::evidence::{反例, 未決定の理由, 検証の方式, 検証結果, 証拠};
use super::super::proposition::{命題, 非空の命題一覧, 非空の命題一覧の生成の失敗};
use super::super::verifier::命題の検証器;
use super::推論規則;

/// 否定の命題を構文検査で、それ以外を有限全数で示す検証器。前提ごとに違う方式が立つ状況を作るために置く。
struct 命題の形で方式を選ぶ検証器;

impl 命題の検証器 for 命題の形で方式を選ぶ検証器 {
    fn 検証する(&self, 命題: &命題) -> 検証結果 {
        let 方式 = if matches!(命題, 命題::否定(_)) { 検証の方式::構文検査 } else { 検証の方式::有限全数 };
        検証結果::証明済み(証拠 {
            方式,
            見た対象の件数: 1,
            説明: "試験の検証器が成立を答えた".to_string(),
        })
    }
}

/// 渡された命題を無条件に反証済みで答える検証器。前提が破れた状況を作るために置く。
struct 常に反証済みで答える検証器;

impl 命題の検証器 for 常に反証済みで答える検証器 {
    fn 検証する(&self, _命題: &命題) -> 検証結果 {
        検証結果::反証済み(反例 {
            方式: 検証の方式::設計関係グラフ,
            説明: "試験の検証器が破れを答えた".to_string(),
            再現の材料: Vec::new(),
        })
    }
}

/// 渡された命題を無条件に未決定で答える検証器。前提の成立も破れも確定しない状況を作るために置く。
struct 常に未決定で答える検証器;

impl 命題の検証器 for 常に未決定で答える検証器 {
    fn 検証する(&self, _命題: &命題) -> 検証結果 {
        検証結果::未決定(未決定の理由::この検証器が扱わない式を含む("試験の検証器".to_string()))
    }
}

fn マーカーを持つ原子() -> 命題 {
    命題::原子から組む(原子命題::マーカーを持つ {
        概念: 項::名指した概念(設計概念の識別子::生成する("blitz_esca::traveler", "旅行者")),
        マーカー名: "Mエンティティ".to_string(),
    })
}

fn 前提が1件の規則(前提: 命題) -> 推論規則 {
    推論規則::生成する("前提が1件の規則", 非空の命題一覧::先頭と残りから生成する(前提, Vec::new()), マーカーを持つ原子().否定する())
}

fn 未決定の理由の説明(結末: &検証結果) -> String {
    let 検証結果::未決定(未決定の理由::推論規則の前提を証明できない(説明)) = 結末 else {
        panic!("前提を証明できない推論規則は、推論規則の前提を証明できない の未決定で答えなければならない: {}", 結末.表記());
    };
    説明.clone()
}

#[test]
fn 前提が0件の推論規則は組めない() {
    assert_eq!(非空の命題一覧::生成する(Vec::new()), Err(非空の命題一覧の生成の失敗::並びが空である));
    assert_eq!(前提が1件の規則(マーカーを持つ原子()).前提一覧.件数(), 1);
}

#[test]
fn 複数の方式の前提から導いた証拠は推論を名乗り前提の方式を説明へ並べる() {
    let 前提一覧 = 非空の命題一覧::先頭と残りから生成する(マーカーを持つ原子(), vec![マーカーを持つ原子().否定する()]);
    let 規則 = 推論規則::生成する("方式の違う2件の前提から導く規則", 前提一覧, マーカーを持つ原子());
    let 検証結果::証明済み(証拠) = 規則.前提から結論を導く(&命題の形で方式を選ぶ検証器) else {
        panic!("前提が全部証明済みなら推論規則は証明済みで答えなければならない");
    };
    assert_eq!(証拠.方式, 検証の方式::推論);
    assert_eq!(証拠.見た対象の件数, 2);
    assert!(証拠.説明.contains("有限全数") && 証拠.説明.contains("構文検査"), "証拠の説明が前提を示した2つの方式を並べていない: {}", 証拠.説明);
}

#[test]
fn 前提が反証済みのときと未決定のときで未決定の理由の説明が読み分けられる() {
    let 規則 = 前提が1件の規則(マーカーを持つ原子());
    let 反証された前提の説明 = 未決定の理由の説明(&規則.前提から結論を導く(&常に反証済みで答える検証器));
    let 確定しない前提の説明 = 未決定の理由の説明(&規則.前提から結論を導く(&常に未決定で答える検証器));
    assert!(反証された前提の説明.contains("反証された"), "前提が反証されたことが説明から読めない: {反証された前提の説明}");
    assert!(確定しない前提の説明.contains("成立も破れも確定しなかった"), "前提が確定しなかったことが説明から読めない: {確定しない前提の説明}");
    assert!(!確定しない前提の説明.contains("反証された"), "確定しなかった前提を反証されたと読める説明になっている: {確定しない前提の説明}");
}
