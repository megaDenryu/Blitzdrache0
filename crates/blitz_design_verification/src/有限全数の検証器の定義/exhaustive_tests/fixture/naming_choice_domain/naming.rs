//! 名指しを選ぶ領域が、選び方に応じて状態とコマンドと出来事を名指す工程。
//!
//! 親のファイルから分けるのは、親が持つのが領域の型と選び方の語彙であり、こちらが持つのが
//! 選び方1つ1つがどの名前を与えるかだからである(CLAUDE.md「切り出しの根拠義務」の5号)。

use super::{名指しの選び方, 名指しを選ぶ領域, 地点, 地点の出来事, 地点の名前の空間, 地点の操作};
use crate::設計概念への参照;

impl 名指しを選ぶ領域 {
    /// 状態の名指し。繋いだ表記が紛れる選び方では、区切りの語と名前の空間の表記を名前の中へ入れる。
    pub(super) fn 状態の名指しを組む(&self, 状態: &地点) -> 設計概念への参照 {
        let 表記 = match (self.名指しの選び方(), 状態) {
            (名指しの選び方::繋いだ表記が紛れる名前にする, 地点::甲) => "甲".to_string(),
            (名指しの選び方::繋いだ表記が紛れる名前にする, 地点::乙) => format!("甲へ{地点の名前の空間}::乙"),
            (_, 地点::甲) => "地点(甲)".to_string(),
            (_, 地点::乙) => "地点(乙)".to_string(),
        };
        概念へ写す(&表記)
    }

    /// コマンドの名指し。2つのコマンドへ同じ名前を与える選び方を持つ。
    pub(super) fn コマンドの名指しを組む(&self, コマンド: &地点の操作) -> 設計概念への参照 {
        let 表記 = match (self.名指しの選び方(), コマンド) {
            (名指しの選び方::コマンドを同じ名前にまとめる, _) => "地点の操作(同じ名前)".to_string(),
            (名指しの選び方::繋いだ表記が紛れる名前にする, 地点の操作::甲へ動く) => format!("乙へ{地点の名前の空間}::丙"),
            (名指しの選び方::繋いだ表記が紛れる名前にする, 地点の操作::乙へ動く) => "丙".to_string(),
            (_, 地点の操作::甲へ動く) => "地点の操作(甲へ動く)".to_string(),
            (_, 地点の操作::乙へ動く) => "地点の操作(乙へ動く)".to_string(),
        };
        概念へ写す(&表記)
    }

    /// 出来事の名指し。2つの出来事へ同じ名前を与える選び方を持つ。
    pub(super) fn 出来事の名指しを組む(&self, 出来事: &地点の出来事) -> 設計概念への参照 {
        let 表記 = match (self.名指しの選び方(), 出来事) {
            (名指しの選び方::出来事を同じ名前にまとめる, _) => "地点の出来事(同じ名前)",
            (_, 地点の出来事::甲へ動いた) => "地点の出来事(甲へ動いた)",
            (_, 地点の出来事::乙へ動いた) => "地点の出来事(乙へ動いた)",
        };
        概念へ写す(表記)
    }
}

// この領域の名前の空間に置いた、実行時のドメイン概念への参照。
fn 概念へ写す(表記: &str) -> 設計概念への参照 {
    設計概念への参照::実行時のドメイン概念として生成する(地点の名前の空間, 表記)
}
