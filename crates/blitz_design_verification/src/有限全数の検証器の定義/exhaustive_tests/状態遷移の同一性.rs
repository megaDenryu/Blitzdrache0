//! 表示が同じ別の参照から組んだ状態遷移を、量化と項の照合が取り違えないことを固定する。
use crate::発生命題;
use crate::*;

fn 全称を確かめる(甲: 設計概念の識別用情報, 乙: 設計概念の識別用情報) {
    assert_eq!(甲.表記(), 乙.表記());
    assert_ne!(甲, 乙);
    let 入力 = 設計概念の識別用情報::型として生成する("題材", "入力");
    let 事象 = 設計概念の識別用情報::型として生成する("題材", "事象");
    let 甲の識別子 = 状態遷移の識別子::前状態と入力から生成する(甲.clone(), 入力.clone());
    let 乙の識別子 = 状態遷移の識別子::前状態と入力から生成する(乙.clone(), 入力.clone());
    assert_ne!(甲の識別子.設計概念の識別用情報として表す(), 乙の識別子.設計概念の識別用情報として表す());
    let 材料 = |識別子| 状態遷移の材料::生成する(識別子, 入力.clone());
    let モデル = 状態遷移モデル::生成する(
        vec![甲.clone(), 乙.clone()],
        vec![状態遷移::成功として生成する(材料(甲の識別子), 甲, vec![事象.clone()]), 状態遷移::成功として生成する(材料(乙の識別子), 乙, Vec::new())],
    );
    let 検証器 = 有限全数の検証器::生成する(探索が組んだ状態遷移モデルと網羅性 {
        モデル,
        網羅性: 数え上げの網羅性::全件を数え上げた,
    });
    let 変数 = 束縛変数::生成する("状態遷移");
    let 全称 = 命題::全称を組む(
        変数.clone(),
        量化の対象集合::到達可能な状態遷移,
        命題::原子から組む(原子命題::発生命題(発生命題::生成する(項::束縛変数(変数), 項::名指した概念(事象)))),
    );
    assert!(検証器.検証する(&全称).反証済みか());
}

#[test]
fn 種類が違う状態の状態遷移を区別する() {
    全称を確かめる(設計概念の識別用情報::型として生成する("題材", "状態"), 設計概念の識別用情報::トレイトとして生成する("題材", "状態"));
}

#[test]
fn 名前空間が違う状態の状態遷移を区別する() {
    全称を確かめる(設計概念の識別用情報::型として生成する("題材", "状態"), 設計概念の識別用情報::実行時のドメイン概念として生成する("題材", "状態"));
}

#[test]
fn 所有者とモジュールの区切りが違う状態の状態遷移を区別する() {
    全称を確かめる(
        設計概念の識別用情報::型として生成する("題材::所有者", "状態"),
        設計概念の識別用情報::型として生成する("題材", "状態").所有者を添える(vec!["所有者".to_string()]),
    );
}
