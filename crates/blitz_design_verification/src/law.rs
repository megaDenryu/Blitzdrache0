//! 法則(Issue #173。層5)。法則を2種類に分ける。
//!
//! 普遍命題としての法則は、検証器へそのまま渡せる1つの命題である。推論規則は、前提の命題が全部証明済みのときに
//! 結論を導くものであり、結論そのものを検証器へ渡しても解けるとは限らない。2つを1つの型へ混ぜると、
//! 「検証器が示した成立」と「規則が導いた成立」が同じ証拠の形で並び、どちらの根拠でその結論が立ったのかが読めなくなる。
//!
//! **推論規則が導いた結論の証拠は `検証の方式::推論` を名乗る。** 前提を示した方式のどれか1つを引き継ぐと、
//! その結論がその方式で直に示されたものと読める。複数の方式の前提から導いたなら、なおさら最初の1件の方式は結論の出自を表さない。
//! 前提を示した方式の一覧は証拠の説明の文が並べる。
//!
//! **0件の前提を持つ推論規則を作れない。** 前提が0件なら、前提を全部証明したという条件がループを1回も回らずに成り立ち、
//! 任意の結論を証明済みにできる。前提一覧を `非空の命題一覧` で持つことがこの偽の証明を型で止める。
//! 参照: `_doc/設計/設計オントロジー.md` 第8節。

mod exclusive_rule;
#[cfg(test)]
mod inference_tests;

pub use exclusive_rule::排他の推論規則;

use super::evidence::{反例, 未決定の理由, 検証の方式, 検証結果, 証拠};
use super::proposition::{命題, 非空の命題一覧};
use super::verifier::命題の検証器;

/// 名前と1つの命題を持つ法則。検証器へそのまま渡せる。
pub struct 普遍命題としての法則 {
    名前: String,
    命題: 命題,
}

/// 前提の命題の並びと結論の命題を持つ規則。前提が全部証明済みなら結論を導く。
pub struct 推論規則 {
    名前: String,
    前提一覧: 非空の命題一覧,
    結論: 命題,
}

impl 普遍命題としての法則 {
    /// 名前と命題から法則を組む。
    pub fn 生成する(名前: &str, 命題: 命題) -> Self {
        Self { 名前: 名前.to_string(), 命題 }
    }

    /// 法則の名前。
    pub fn 名前(&self) -> &str {
        &self.名前
    }

    /// 検証器へ渡す命題。
    pub fn 命題(&self) -> &命題 {
        &self.命題
    }
}

impl 推論規則 {
    /// 名前と前提の並びと結論から規則を組む。前提の並びを `非空の命題一覧` で受けるのは、0件の前提を持つ規則が
    /// 任意の結論を証明済みにできるためである。0件を拒む関数は `非空の命題一覧::生成する` の側に在り、そこが型付きエラーを返す。
    pub fn 生成する(名前: &str, 前提一覧: 非空の命題一覧, 結論: 命題) -> Self {
        Self {
            名前: 名前.to_string(), 前提一覧, 結論
        }
    }

    /// 規則の名前。
    pub fn 名前(&self) -> &str {
        &self.名前
    }

    /// 規則が導く結論の命題。
    pub fn 結論(&self) -> &命題 {
        &self.結論
    }

    /// 前提を全部検証し、全部証明済みなら結論を導いたことを証拠で答える。
    /// 前提を1つでも証明できないなら結論について何も言えないため、反証済みでなく未決定で答える。
    pub fn 前提から結論を導く(&self, 検証器: &dyn 命題の検証器) -> 検証結果 {
        let mut 前提を示した方式一覧 = Vec::new();
        for 前提 in self.前提一覧.一覧() {
            match 検証器.検証する(前提) {
                検証結果::証明済み(証拠) => 前提を示した方式一覧.push(証拠.方式),
                検証結果::反証済み(反例) => return 検証結果::未決定(self.前提が反証された理由(前提, &反例)),
                検証結果::未決定(理由) => return 検証結果::未決定(self.前提が確定しなかった理由(前提, &理由)),
            }
        }
        検証結果::証明済み(self.導出の証拠を組む(&前提を示した方式一覧))
    }

    /// 前提が反証されたときの未決定の理由。結論が偽であると示したのではないことを説明の文が言う。
    fn 前提が反証された理由(&self, 前提: &命題, 反例: &反例) -> 未決定の理由 {
        未決定の理由::推論規則の前提を証明できない(format!("推論規則「{}」の前提({})は反証された(前提が破れたのであって、結論が偽であると示したのではない): {}", self.名前, 前提.表記(), 反例.説明))
    }

    /// 前提の成立も破れも確定しなかったときの未決定の理由。反証されたときと説明の文で読み分けられる。
    fn 前提が確定しなかった理由(&self, 前提: &命題, 理由: &未決定の理由) -> 未決定の理由 {
        未決定の理由::推論規則の前提を証明できない(format!("推論規則「{}」の前提({})は成立も破れも確定しなかった: {理由:?}", self.名前, 前提.表記()))
    }

    /// 導出であることが分かる説明を持つ証拠。方式は `推論` であり、前提を示した方式は説明の文が並べる。
    fn 導出の証拠を組む(&self, 前提を示した方式一覧: &[検証の方式]) -> 証拠 {
        証拠 {
            方式: 検証の方式::推論,
            見た対象の件数: self.前提一覧.件数(),
            説明: format!(
                "推論規則「{}」が{}件の前提から結論({})を導いた(検証器が結論を直に示したのではない)。前提を示した方式: {}",
                self.名前,
                self.前提一覧.件数(),
                self.結論.表記(),
                Self::方式の一覧を綴る(前提を示した方式一覧)
            ),
        }
    }

    /// 前提を示した方式を、前提の並びの順で1行へ綴る。
    fn 方式の一覧を綴る(方式一覧: &[検証の方式]) -> String {
        方式一覧.iter().map(|方式| format!("{方式:?}")).collect::<Vec<String>>().join("・")
    }
}
