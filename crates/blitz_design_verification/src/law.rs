//! 法則(Issue #173。層5)。法則を2種類に分ける。
//!
//! 普遍命題としての法則は、検証器へそのまま渡せる1つの命題である。推論規則は、前提の命題が全部証明済みのときに
//! 結論を導くものであり、結論そのものを検証器へ渡しても解けるとは限らない。2つを1つの型へ混ぜると、
//! 「検証器が示した成立」と「規則が導いた成立」が同じ証拠の形で並び、どちらの根拠でその結論が立ったのかが読めなくなる。
//!
//! 推論規則が導いた結論の証拠は、前提を示した方式をそのまま名乗りつつ、導出であることが分かる説明を持つ。
//! 参照: `_doc/設計/設計オントロジー.md` 第8節。

mod exclusive_rule;

pub use exclusive_rule::排他の推論規則;

use super::evidence::{未決定の理由, 検証の方式, 検証結果, 証拠};
use super::proposition::命題;
use super::verifier::命題の検証器;

/// 名前と1つの命題を持つ法則。検証器へそのまま渡せる。
pub struct 普遍命題としての法則 {
    名前: String,
    命題: 命題,
}

/// 前提の命題の並びと結論の命題を持つ規則。前提が全部証明済みなら結論を導く。
pub struct 推論規則 {
    名前: String,
    前提一覧: Vec<命題>,
    結論: 命題,
}

impl 普遍命題としての法則 {
    /// 名前と命題から法則を組む。
    pub fn 生成する(名前: &str, 命題: 命題) -> Self {
        Self { 名前: 名前.to_string(), 命題 }
    }

    /// 法則の名前。
    pub fn 名前(&self) -> &str {
        &self.名前
    }

    /// 検証器へ渡す命題。
    pub fn 命題(&self) -> &命題 {
        &self.命題
    }
}

impl 推論規則 {
    /// 名前と前提の並びと結論から規則を組む。
    pub fn 生成する(名前: &str, 前提一覧: Vec<命題>, 結論: 命題) -> Self {
        Self {
            名前: 名前.to_string(), 前提一覧, 結論
        }
    }

    /// 規則の名前。
    pub fn 名前(&self) -> &str {
        &self.名前
    }

    /// 規則が導く結論の命題。
    pub fn 結論(&self) -> &命題 {
        &self.結論
    }

    /// 前提を全部検証し、全部証明済みなら結論を導いたことを証拠で答える。
    /// 前提が1つでも成立しないなら結論について何も言えないため、反証済みでなく未決定で答える。
    pub fn 前提から結論を導く(&self, 検証器: &dyn 命題の検証器) -> 検証結果 {
        let mut 前提の方式 = 検証の方式::構文検査;
        for (順番, 前提) in self.前提一覧.iter().enumerate() {
            match 検証器.検証する(前提) {
                検証結果::証明済み(証拠) => {
                    if 順番 == 0 {
                        前提の方式 = 証拠.方式;
                    }
                }
                成立しない結末 => return 検証結果::未決定(self.前提が成立しない理由(前提, &成立しない結末)),
            }
        }
        検証結果::証明済み(self.導出の証拠を組む(前提の方式))
    }

    fn 前提が成立しない理由(&self, 前提: &命題, 結末: &検証結果) -> 未決定の理由 {
        未決定の理由::推論規則の前提が成立していない(format!("推論規則「{}」の前提({})が成立していない: {}", self.名前, 前提.表記(), 結末.表記()))
    }

    /// 導出であることが分かる説明を持つ証拠。方式は最初の前提を示した方式を引き継ぐ。
    fn 導出の証拠を組む(&self, 前提の方式: 検証の方式) -> 証拠 {
        証拠 {
            方式: 前提の方式,
            見た対象の件数: self.前提一覧.len(),
            説明: format!("推論規則「{}」が{}件の前提から結論({})を導いた(検証器が結論を直に示したのではない)", self.名前, self.前提一覧.len(), self.結論.表記()),
        }
    }
}
