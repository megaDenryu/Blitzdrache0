//! 状態遷移モデルとは、初期状態の一覧と状態遷移の一覧から成る、振る舞いの命題の検証の対象になるモデルのことである。
//!
//! 静的な設計関係グラフは「どの型がどの型を保持するか」を答えるが、「ある条件の状態から状態遷移を行うとどの出来事が成立するか」を答えない。
//! この型が時間の向きを持つ対象を受け持ち、状態と状態遷移を数え上げるメソッドを有限全数の検証器へ渡す。
//! 参照: Issue #173「時間と遷移」「到達可能性」。

#[path = "状態遷移モデルの定義/到達可能な状態一覧の定義.rs"]
mod 到達可能な状態一覧の定義;
#[path = "状態遷移モデルの定義/状態遷移の定義.rs"]
mod 状態遷移の定義;
#[path = "状態遷移モデルの定義/状態遷移の識別子の定義.rs"]
mod 状態遷移の識別子の定義;

pub use 到達可能な状態一覧の定義::到達可能な状態一覧;
pub use 状態遷移の定義::{状態遷移, 状態遷移の材料};
pub use 状態遷移の識別子の定義::状態遷移の識別子;

use crate::設計概念の識別用情報;

/// 初期状態と状態遷移の全体。
#[derive(Debug, Clone, Default)]
pub struct 状態遷移モデル {
    初期状態一覧: Vec<設計概念の識別用情報>,
    状態遷移一覧: Vec<状態遷移>,
}

impl 状態遷移モデル {
    /// 初期状態の一覧と状態遷移の一覧からモデルを組む。
    pub fn 生成する(初期状態一覧: Vec<設計概念の識別用情報>, 状態遷移一覧: Vec<状態遷移>) -> Self {
        Self { 初期状態一覧, 状態遷移一覧 }
    }

    /// 初期状態の一覧。
    pub fn 初期状態一覧(&self) -> &[設計概念の識別用情報] {
        &self.初期状態一覧
    }

    /// モデルが持つ状態遷移の全件。到達しない状態遷移も含む。
    pub fn 状態遷移一覧(&self) -> &[状態遷移] {
        &self.状態遷移一覧
    }

    /// 初期状態から辿って到達できる状態の一覧を組む。
    pub fn 到達可能な状態一覧を組む(&self) -> 到達可能な状態一覧 {
        到達可能な状態一覧::幅優先で組む(&self.初期状態一覧, &self.状態遷移一覧)
    }

    /// 前状態が到達可能な状態遷移だけを、モデルの並び順で集める。
    pub fn 到達可能な状態遷移一覧(&self) -> Vec<&状態遷移> {
        let 到達可能な状態一覧 = self.到達可能な状態一覧を組む();
        self.状態遷移一覧.iter().filter(|候補| 到達可能な状態一覧.含むか(候補.前状態())).collect()
    }

    /// 状態遷移を、項へ写した設計概念の識別用情報から引き当てる。命題の項に入った状態遷移をモデルの1件へ戻す唯一のメソッドである。
    pub fn 項から状態遷移を引き当てる(&self, 項の概念: &設計概念の識別用情報) -> Option<&状態遷移> {
        self.状態遷移一覧.iter().find(|候補| &候補.識別子().設計概念の識別用情報として表す() == 項の概念)
    }
}
