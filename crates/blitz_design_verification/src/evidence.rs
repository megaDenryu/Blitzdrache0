//! 検証結果とは、1つの命題について検証器が答えた結末のことである。証明済み・反証済み・未決定の3つを区別する。
//!
//! **`bool` を返す検証器の口を作らない。** 真偽の2値では、「全対象について成立を示せた」と「この検証器では成立も反例も確定できなかった」が
//! 同じ偽へ潰れる。潰すと、反例の探索で反例が出なかっただけの命題を証明済みと呼ぶ誤りを型が止められない。
//! 有限の対象を全部列挙できたときだけ証明済みとし、生成による一部の探索は「未決定。探索の範囲では反例が無い」とする。
//!
//! **対象集合が0件の全称も、検査器としては証明済みにしない。** 空集合上の全称は論理としては真だが、検査器がそれを
//! 証明済みで答えると、まだ1件も実装が無い設計解釈マーカーについての全称が全部通る。これは本節が止めた
//! 「反例なし」と「証明済み」の混同そのものであり、`対象集合が空である` の未決定で答える。
//! 同じ理由で、定義をたどれずモジュールパスが空のまま節点になった概念に触れた評価も
//! `型の定義のモジュールパスが未解決である` の未決定で答え、偽の反証を出さない。
//! 参照: `_doc/設計/設計オントロジー.md` 第9節。

/// 命題1つについての検証の結末。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 検証結果 {
    /// 対象を全部見て成立を示した。
    証明済み(証拠),
    /// 成立しない実例を1件見つけた。
    反証済み(反例),
    /// この検証器では成立も反例も確定できなかった。
    未決定(未決定の理由),
}

/// 証明済みの根拠。どの方式で、何を全部見たかを持つ。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 証拠 {
    /// 成立を示した手立て。
    pub 方式: 検証の方式,
    /// 全部見た対象の件数。構造の検証では照合した関係の件数、有限全数では列挙した状態と遷移の件数である。
    pub 見た対象の件数: usize,
    /// 人が読む1行。「対象の32件の遷移を全部列挙した」の形である。
    pub 説明: String,
}

/// 反証済みの根拠。人が再現できる材料を持つ。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 反例 {
    /// 反例を見つけた手立て。
    pub 方式: 検証の方式,
    /// 何が期待と違ったかを人へ伝える1行。
    pub 説明: String,
    /// 前状態・入力・遷移・得られた出来事・期待した出来事のような、名前と値の対。人がその状況へ戻るために持つ。
    pub 再現の材料: Vec<(String, String)>,
}

/// 未決定である理由。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 未決定の理由 {
    /// 対象集合を有限に列挙できなかった。
    有限に列挙できない(String),
    /// この検証器が解かない式を含んでいた。
    この検証器が扱わない式を含む(String),
    /// 見た範囲では反例も証人も出なかったが、見ていない範囲が残っている。
    探索の範囲では反例が無い {
        /// 実際に見た対象の件数。
        探索した件数: usize,
        /// なぜ見ていない範囲が残るのかを人へ伝える文。数え上げの網羅性の表記がここへ入る。
        探索の範囲の説明: String,
    },
    /// 命題が名指した概念が設計関係グラフにも遷移モデルにも無かった。
    対象の概念がグラフに無い(String),
    /// 全称の対象集合を列挙した件数が0件だった。
    対象集合が空である(String),
    /// 抽出器が型の定義をたどれず、モジュールパスが空のまま節点になっていた。
    型の定義のモジュールパスが未解決である(String),
    /// 推論規則の前提が1つ以上成立していなかった。
    推論規則の前提が成立していない(String),
}

/// 証明済みまたは反証済みを示した検証の手立て。記号実行とSMTはこの列挙に選択肢として在るが、実装は別のissueが設計する。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum 検証の方式 {
    /// 型検査が通ったこと自体が根拠である。
    コンパイラ,
    /// ソースの構文の走査が根拠である。
    構文検査,
    /// 抽出済みの設計関係グラフへの問いが根拠である。
    設計関係グラフ,
    /// 状態と遷移を全部列挙したことが根拠である。
    有限全数,
    /// 生成した入力で反例を探したことが根拠である。
    反例の探索,
    /// 記号実行が根拠である。実装は別のissueが設計する。
    記号実行,
    /// 充足可能性判定の解き手が根拠である。実装は別のissueが設計する。
    SMT,
}

impl 検証結果 {
    /// 証明済みであるか。合否の集計だけがこの問いを使い、検証器の内側はこの問いを使わない。
    pub const fn 証明済みか(&self) -> bool {
        matches!(self, Self::証明済み(_))
    }

    /// 反証済みであるか。
    pub const fn 反証済みか(&self) -> bool {
        matches!(self, Self::反証済み(_))
    }

    /// 人が読む1行の表記。
    pub fn 表記(&self) -> String {
        match self {
            Self::証明済み(証拠) => format!("証明済み({:?}): {}", 証拠.方式, 証拠.説明),
            Self::反証済み(反例) => format!("反証済み({:?}): {}", 反例.方式, 反例.説明),
            Self::未決定(理由) => format!("未決定: {理由:?}"),
        }
    }
}
