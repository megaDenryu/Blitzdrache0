//! 数え上げの網羅性とは、ある対象集合を数え上げた並びが取りうる値の全部であるか、その一部に限るかの区別のことである。
//!
//! この区別を持たずに件数だけを持つと、有限個の標本を全部見たことが「全部の値について成立を示した」と読まれる。
//! 連続量(浮動小数の座標・時間)を含む領域では取りうる値を全部並べられないため、並べた標本を全件と呼ばないことをこの型が止める。
//! 上限で打ち切ったときも同じ扱いにするのは、打ち切った先に反例が在るかどうかを見ていないためである。
//! 異なる状態に同じ同一性を与えたときも同じ扱いにするのは、別の状態と同じ同一性を与えられて捨てた状態の先を1件も辿っていないためである。
//! 互いに等しくない2つの値が同じ名指しへ写ったときも同じ扱いにするのは、モデルの上でその2つが1件の節点へ重なり、
//! 別物として辿った状態と遷移を命題の層が区別できなくなるためである。
//! 参照: `_doc/設計/設計オントロジー.md` 第9節。

/// 数え上げた並びが全件であるか、抽出・標本・打ち切り・同一性の欠落によって一部に限るか。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 数え上げの網羅性 {
    /// 取りうる値を全部並べた。この範囲についての全称の成立と存在の不在を答えてよい。
    全件を数え上げた,
    /// 抽出が関係を落としており、関係から集める対象に見ていないものが残る。
    抽出の欠落があり全件と言えない {
        /// 関係を落とした理由と件数。未決定の理由へ渡す。
        説明: String,
    },
    /// 連続量を含み全部は並べられないため標本だけを並べた。
    連続量の標本に限る {
        /// どの量が連続であるかを人へ伝える文の並び。未決定の理由の文へそのまま入る。
        説明一覧: Vec<String>,
    },
    /// 探索してよい状態の件数の上限に達したため、そこで打ち切った。
    上限で打ち切った {
        /// 打ち切りの基準にした、探索してよい状態の件数。
        上限: usize,
    },
    /// 領域が答えた状態の同一性が、互いに等しくない2つの状態を同じ同一性へ写した。探索は2件目を同じ状態として捨てており、辿っていない状態が残る。
    異なる状態に同じ同一性を与えた {
        /// 捨てられた側の状態を人が読む名前の並び。どの状態が別の状態と同じ同一性を与えられたかを読み手が追えるようにする。
        別の状態と同じ同一性を与えられた状態の名前一覧: Vec<String>,
    },
    /// 領域が答えた名指しが、互いに等しくない2つの値を同じ参照へ写した。モデルの上でその2つは1件の節点へ重なる。
    異なる値に同じ名指しを与えた {
        /// 2つ以上の値が写った名指しの表記の並び。どの名前で重なったかを読み手が追えるようにする。
        異なる値に与えられた名指しの表記一覧: Vec<String>,
    },
}

impl 数え上げの網羅性 {
    /// 取りうる値を全部並べたか。全称の成立と存在の不在を答えてよいのはこれが真のときだけである。
    pub const fn 全件を数え上げたか(&self) -> bool {
        matches!(self, Self::全件を数え上げた)
    }

    /// 人が読む1行の表記。未決定の理由の文がこの表記を持ち、なぜ決まらなかったかを読み手へ残す。
    pub fn 表記(&self) -> String {
        match self {
            Self::全件を数え上げた => "取りうる値を全件数え上げた".to_string(),
            Self::抽出の欠落があり全件と言えない { 説明 } => format!("抽出の欠落があり全件と言えない({説明})"),
            Self::連続量の標本に限る { 説明一覧 } => {
                format!("連続量を含むため標本に限る({})", 説明一覧.join(" / "))
            }
            Self::上限で打ち切った { 上限 } => format!("探索してよい状態の件数の上限{上限}件で打ち切った"),
            Self::異なる状態に同じ同一性を与えた {
                別の状態と同じ同一性を与えられた状態の名前一覧,
            } => {
                format!("異なる状態に同じ状態の同一性を与えた({})", 別の状態と同じ同一性を与えられた状態の名前一覧.join(" / "))
            }
            Self::異なる値に同じ名指しを与えた {
                異なる値に与えられた名指しの表記一覧
            } => {
                format!("互いに等しくない2つの値に同じ名指しを与えた({})", 異なる値に与えられた名指しの表記一覧.join(" / "))
            }
        }
    }
}
