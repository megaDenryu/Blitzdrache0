//! 命題の集合(Issue #173。層5)。
//!
//! **型の名前を `仕様` にしない。** Issue #171 の2026-09-20のオーナー裁定が「仕様は実行時のデータの種類ではない」と定めている。
//! 「仕様とは、アプリケーションが満たすべき命題の集合のことである」という定義は設計文書の側が持ち、
//! この型はその集合そのものを表す。
//! 参照: `_doc/設計/設計オントロジー.md` 第8節。

#[cfg(test)]
mod specification_tests;

use super::evidence::{反例, 未決定の理由};
use super::proposition::命題;
use super::verifier::命題の検証器;

/// 名前を付けた命題1件。名前を持つのは、集計の報告がどの命題が反証されたかを名前で指すためである。
pub struct 名前付きの命題 {
    名前: String,
    命題: 命題,
}

/// 名前と、名前付きの命題の並び。
pub struct 命題の集合 {
    名前: String,
    命題一覧: Vec<名前付きの命題>,
}

/// 命題の集合を全件検証した結果の数え上げ。反証済みは名前と反例を残す。
pub struct 検証の集計 {
    /// 証明済みで答えた命題の件数。
    pub 証明済みの件数: usize,
    /// 反証済みで答えた命題の件数。
    pub 反証済みの件数: usize,
    /// 未決定で答えた命題の件数。
    pub 未決定の件数: usize,
    /// 反証済みの命題の名前と反例の対。どの命題が破れたかを名前で指すために持つ。
    pub 反証済みの一覧: Vec<(String, 反例)>,
    /// 未決定の命題の名前と理由の対。件数だけでは読み手が何を解けなかったのかを追えないため、反証済みと対称に持つ。
    pub 未決定の一覧: Vec<(String, 未決定の理由)>,
}

impl 名前付きの命題 {
    /// 名前と命題から1件を組む。
    pub fn 生成する(名前: &str, 命題: 命題) -> Self {
        Self { 名前: 名前.to_string(), 命題 }
    }

    /// 命題の名前。
    pub fn 名前(&self) -> &str {
        &self.名前
    }

    /// 検証器へ渡す命題。
    pub fn 命題(&self) -> &命題 {
        &self.命題
    }
}

impl 命題の集合 {
    /// 集合の名前と命題の並びから組む。
    pub fn 生成する(名前: &str, 命題一覧: Vec<名前付きの命題>) -> Self {
        Self { 名前: 名前.to_string(), 命題一覧 }
    }

    /// 集合の名前。
    pub fn 名前(&self) -> &str {
        &self.名前
    }

    /// 持っている命題の並び。
    pub fn 命題一覧(&self) -> &[名前付きの命題] {
        &self.命題一覧
    }

    /// 全件を検証し、結果ごとに数える。未決定を反証済みへ混ぜない。
    pub fn 全件を検証する(&self, 検証器: &dyn 命題の検証器) -> 検証の集計 {
        let mut 集計 = 検証の集計 {
            証明済みの件数: 0,
            反証済みの件数: 0,
            未決定の件数: 0,
            反証済みの一覧: Vec::new(),
            未決定の一覧: Vec::new(),
        };
        for 名前付き in &self.命題一覧 {
            集計.結果を数える(名前付き.名前(), 検証器.検証する(名前付き.命題()));
        }
        集計
    }
}

impl 検証の集計 {
    fn 結果を数える(&mut self, 名前: &str, 結果: super::evidence::検証結果) {
        match 結果 {
            super::evidence::検証結果::証明済み(_) => self.証明済みの件数 += 1,
            super::evidence::検証結果::反証済み(反例) => {
                self.反証済みの件数 += 1;
                self.反証済みの一覧.push((名前.to_string(), 反例));
            }
            super::evidence::検証結果::未決定(理由) => {
                self.未決定の件数 += 1;
                self.未決定の一覧.push((名前.to_string(), 理由));
            }
        }
    }

    /// 人が読む1行の要約。
    pub fn 表記(&self) -> String {
        format!("証明済み{}件・反証済み{}件・未決定{}件", self.証明済みの件数, self.反証済みの件数, self.未決定の件数)
    }
}
