//! 排他から不発生を導くためのルール: 2つのイベントが排他であるという設計ルールから、一方の発生の成立から他方の不発生を導く具体のルール。
//!
//! 命題の形を問わずに後件を置き換えず、後件が `発生する(?v, 一方)` である全称の含意だけを受ける。
//! 形を問わないと、排他とは関係の無い命題からこの結論を作れてしまい、導出の正しさがルールの外の規律に依ることになる。

use crate::設計概念の識別用情報;

use super::super::proposition::{命題, 非空の命題一覧};
use super::super::原子命題の定義::{原子命題, 発生命題, 項};
use super::結論を導くためのルール;

/// 排他な2つのイベント。
pub struct 排他から不発生を導くためのルール {
    一方: 設計概念の識別用情報,
    他方: 設計概念の識別用情報,
}

impl 排他から不発生を導くためのルール {
    /// 排他な2つのイベントの設計概念の識別用情報からルールを組む。
    pub fn 生成する(一方: 設計概念の識別用情報, 他方: 設計概念の識別用情報) -> Self {
        Self { 一方, 他方 }
    }

    /// 後件が `発生する(?v, 一方)` である全称の含意の成立から、後件を `NOT 発生する(?v, 他方)` へ置き換えた命題を導く。
    /// 形が合わなければ値なしを返す。
    pub fn 発生の否定へ置き換えた命題を導く(&self, 成立した命題: &命題) -> Option<命題> {
        let 命題::全称(全称) = 成立した命題 else {
            return None;
        };
        let 命題::含意(含意) = 全称.本体() else {
            return None;
        };
        let 命題::原子(原子) = 含意.後件() else {
            return None;
        };
        let 原子命題::発生命題(発生) = 原子.as_ref() else {
            return None;
        };
        if *発生.状態遷移() != 項::束縛変数(全称.束縛().clone()) || *発生.イベント() != 項::名指した概念(self.一方.clone()) {
            return None;
        }
        Some(命題::全称を組む(
            全称.束縛().clone(),
            全称.量化の対象集合().clone(),
            命題::含意を組む(含意.前件().clone(), self.他方の不発生を組む(発生.状態遷移())),
        ))
    }

    /// 成立した命題と同じ状態遷移について、他方のイベントが発生しないという命題を組む。
    pub fn 他方の不発生を組む(&self, 状態遷移: &項) -> 命題 {
        命題::原子から組む(原子命題::発生命題(発生命題::生成する(状態遷移.clone(), 項::名指した概念(self.他方.clone())))).否定する()
    }

    /// このルールを、成立した命題を前提とし置き換えた命題を結論とする、結論を導くためのルールへ写す。
    /// 形が合わなければ値なしを返す。
    pub fn 結論を導くためのルールへ写す(&self, 成立した命題: &命題) -> Option<結論を導くためのルール> {
        let 結論 = self.発生の否定へ置き換えた命題を導く(成立した命題)?;
        let 前提一覧 = 非空の命題一覧::先頭と残りから生成する(成立した命題.clone(), Vec::new());
        Some(結論を導くためのルール::生成する(&format!("{}と{}は排他である", self.一方.表記(), self.他方.表記()), 前提一覧, 結論))
    }
}
