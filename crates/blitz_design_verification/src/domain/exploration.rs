//! 領域を探索して遷移モデルを組む工程の、入力(探索の上限)と出力(探索が組んだ遷移モデルと網羅性)と入口。
//!
//! 探索そのものは `breadth_first` が持ち、辿る状態の台帳は `state_ledger` が、名指しの台帳は `naming_ledger` が持つ。入口をこのファイルへ置くのは、
//! 呼び出し側が探索の内側の持ち物(待ち行列・同一性ごとの代表の状態・名指しごとの代表の値・連続量の説明の蓄積)を1つも知らずに呼べることを保つためである。

mod breadth_first;
mod coverage_basis;
mod naming_ledger;
mod state_ledger;

use breadth_first::幅優先の探索;

use super::有限に数え上げられる領域;
use crate::{数え上げの網羅性, 遷移モデル};

/// 探索してよい状態の件数の既定の上限。状態1件ごとにコマンドの件数ぶん実物の遷移関数を呼ぶため、
/// 1万件を超えると1回の検証が人が待てる時間を超える。上限に達したときは網羅性が打ち切りを名乗るため、
/// 超えたことが黙って通り過ぎることは無い。
const 既定の探索してよい状態の件数: usize = 10_000;

/// 探索してよい状態の件数の上限。裸の `usize` で受けないのは、状態の件数・遷移の件数・出来事の件数という同型の数が
/// 同じ工程を流れ、引数として並べると取り違えても型が通るためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 探索の上限(usize);

/// 探索が組んだ遷移モデルと、その数え上げが全件だったかどうか。
#[derive(Debug, Clone)]
pub struct 探索が組んだ遷移モデルと網羅性 {
    /// 探索が組んだ遷移モデル。
    pub モデル: 遷移モデル,
    /// その数え上げが取りうる値の全件だったか、標本に限るか、上限で打ち切ったか。
    pub 網羅性: 数え上げの網羅性,
}

impl 探索の上限 {
    /// 探索してよい状態の件数から上限を組む。
    pub const fn 生成する(状態の件数: usize) -> Self {
        Self(状態の件数)
    }

    /// 探索してよい状態の件数。
    pub const fn 状態の件数(self) -> usize {
        self.0
    }
}

impl Default for 探索の上限 {
    fn default() -> Self {
        Self(既定の探索してよい状態の件数)
    }
}

/// 領域を初期状態から幅優先で探索し、遷移モデルと数え上げの網羅性を返す。
pub fn 領域から遷移モデルを組む<領域型: 有限に数え上げられる領域>(領域: &領域型, 上限: 探索の上限) -> 探索が組んだ遷移モデルと網羅性 {
    let mut 探索 = 幅優先の探索::生成する(領域, 上限);
    探索.初期状態から辿る();
    探索.遷移モデルと網羅性を組み立てる()
}
