//! 探索が領域へ名指しを頼むときに通す台帳。名指しごとに代表の値を1件控え、
//! 代表と等しくない値が同じ名指しへ写った事実を残す。
//!
//! 名指しを単射にするのは領域の側の仕事だが、**畳む名指しを書けること自体は止められない**。止められないため、
//! 畳んだ結果が `全件を数え上げた` を名乗れないようにする。これは状態の同一性の畳みに対して既に採ってある形と同じである
//! 参照: `crates/blitz_design_verification/src/domain/exploration/state_ledger.rs`。
//!
//! 探索の側へ平らに置かず1つの台帳にするのは、名指しを頼む口と畳みを数える口が別々の場所に在ると、
//! 名指しを1箇所で頼み忘れても型が通るためである。探索は領域へ直に名指しを頼まず、必ずこの台帳を通す。
//!
//! 規則の名指しをこの台帳へ通さないのは、`規則を名指す` が引数を取らず領域あたり1件しか返さないためである。
//! 1件しか無いものは、互いに等しくない2つの値が同じ名指しへ写るという事象を持たない。

use std::collections::HashMap;
use std::collections::hash_map::Entry;

use super::super::有限に数え上げられる領域;
use crate::設計概念への参照;

// 1つの名指しにつき代表の値を1件控える帳面。代表と等しくない値が同じ名指しへ写ったら、その名指しの表記を残す。
struct 名指しごとの代表<値: Clone + PartialEq> {
    名指しごとの代表の値: HashMap<設計概念への参照, 値>,
    畳まれた名指しの表記一覧: Vec<String>, // 同じ表記は1度だけ残す
}

/// 状態とコマンドと出来事の名指しを、畳みを数えながら答える台帳。
pub(super) struct 名指しの台帳<'領域, 領域型: 有限に数え上げられる領域> {
    領域: &'領域 領域型,
    状態: 名指しごとの代表<領域型::状態>,
    コマンド: 名指しごとの代表<領域型::コマンド>,
    出来事: 名指しごとの代表<領域型::出来事>,
}

impl<値: Clone + PartialEq> 名指しごとの代表<値> {
    fn 生成する() -> Self {
        Self {
            名指しごとの代表の値: HashMap::new(),
            畳まれた名指しの表記一覧: Vec::new(),
        }
    }

    fn 控える(&mut self, 名指し: &設計概念への参照, 値: &値) {
        match self.名指しごとの代表の値.entry(名指し.clone()) {
            Entry::Vacant(空き) => {
                空き.insert(値.clone());
            }
            Entry::Occupied(代表) => {
                if 代表.get() != 値 {
                    let 表記 = 名指し.表記();
                    if !self.畳まれた名指しの表記一覧.contains(&表記) {
                        self.畳まれた名指しの表記一覧.push(表記);
                    }
                }
            }
        }
    }
}

impl<'領域, 領域型: 有限に数え上げられる領域> 名指しの台帳<'領域, 領域型> {
    pub(super) fn 生成する(領域: &'領域 領域型) -> Self {
        Self {
            領域,
            状態: 名指しごとの代表::生成する(),
            コマンド: 名指しごとの代表::生成する(),
            出来事: 名指しごとの代表::生成する(),
        }
    }

    /// 状態を領域へ名指してもらい、その名指しを控える。
    pub(super) fn 状態を名指す(&mut self, 状態: &領域型::状態) -> 設計概念への参照 {
        let 名指し = self.領域.状態を名指す(状態);
        self.状態.控える(&名指し, 状態);
        名指し
    }

    /// コマンドを領域へ名指してもらい、その名指しを控える。
    pub(super) fn コマンドを名指す(&mut self, コマンド: &領域型::コマンド) -> 設計概念への参照 {
        let 名指し = self.領域.コマンドを名指す(コマンド);
        self.コマンド.控える(&名指し, コマンド);
        名指し
    }

    /// 出来事を領域へ名指してもらい、その名指しを控える。
    pub(super) fn 出来事を名指す(&mut self, 出来事: &領域型::出来事) -> 設計概念への参照 {
        let 名指し = self.領域.出来事を名指す(出来事);
        self.出来事.控える(&名指し, 出来事);
        名指し
    }

    /// 互いに等しくない2つの値が同じ名指しへ写った、その名指しの表記の並び。空なら畳みは1度も起きていない。
    pub(super) fn 畳まれた名指しの表記一覧へ渡す(self) -> Vec<String> {
        let mut 並び = self.状態.畳まれた名指しの表記一覧;
        並び.extend(self.コマンド.畳まれた名指しの表記一覧);
        並び.extend(self.出来事.畳まれた名指しの表記一覧);
        並び
    }
}
