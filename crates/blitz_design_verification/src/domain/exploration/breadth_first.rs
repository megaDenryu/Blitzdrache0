//! 領域を初期状態から幅優先で辿り、実物の遷移関数を呼んで遷移モデルを組む探索。
//!
//! 辿る状態の台帳・名指しの台帳・組んだ遷移の並び・数え上げの網羅性の根拠の4つを探索自身が所有する。
//! これらを引数で引き回すと、辿る工程を1つ足すたびに全部の署名へ足すことになり、どの工程がどれを変えるかが読めなくなる。
//! 探索は領域を借りるだけであり、状態の中身を1つも解釈しない(解釈するのは領域の側の `状態の同一性を答える` と `状態を名指す` である)。
//!
//! **済みの集合の鍵は `状態の同一性を答える` の答えであり、`状態を名指す` の名前ではない。** 同一性も名指しも領域が書く以上、
//! 異なる値を同じ答えへ写す実装は書ける。書けること自体は止められないため、**この探索は2つの台帳で、異なる状態に同じ同一性を与えたことと
//! 異なる値に同じ名指しを与えたことを検出し、それが起きた数え上げに `全件を数え上げた` を名乗らせない**。嘘をつける経路を残したまま、嘘をついた結果が全件を名乗れないようにする形である。
//! 名指しは必ず名指しの台帳を通して頼み、領域へ直に頼まない(通さない経路が1つでも在ると、そこで異なる値に同じ名指しを与えたことだけが数えられない)。

use super::super::{数え上げ, 有限に数え上げられる領域, 遷移の帰結};
use super::coverage_basis::数え上げの網羅性の根拠;
use super::naming_ledger::名指しの台帳;
use super::state_ledger::辿る状態の台帳;
use super::{探索が組んだ遷移モデルと網羅性, 探索の上限};
use crate::{設計概念への参照, 遷移, 遷移の材料, 遷移の識別子, 遷移モデル};

#[cfg(test)]
#[path = "breadth_first/失敗の同一性.rs"]
mod 失敗の同一性;

// 遷移が失敗したことを表す節点の名前の空間。領域が名指すドメインの概念と同じ空間へ入れないのは、
// 失敗の節点が探索の側で組む名前であり、実在の概念の名前と衝突させないためである。
const 遷移が失敗した節点の名前の空間: &str = "設計の検証の探索";

pub(super) struct 幅優先の探索<'領域, 領域型: 有限に数え上げられる領域> {
    領域: &'領域 領域型,
    上限: 探索の上限,
    辿る状態の台帳: 辿る状態の台帳<'領域, 領域型>,
    名指しの台帳: 名指しの台帳<'領域, 領域型>,
    初期状態一覧: Vec<設計概念への参照>,
    遷移一覧: Vec<遷移>,
    網羅性の根拠: 数え上げの網羅性の根拠,
}

impl<'領域, 領域型: 有限に数え上げられる領域> 幅優先の探索<'領域, 領域型> {
    pub(super) fn 生成する(領域: &'領域 領域型, 上限: 探索の上限) -> Self {
        let 初期状態の数え上げ: 数え上げ<領域型::状態> = 領域.初期状態を数え上げる();
        let mut 網羅性の根拠 = 数え上げの網羅性の根拠::生成する();
        網羅性の根拠.連続量の説明を控える(初期状態の数え上げ.連続量の説明());
        let mut 名指しの台帳 = 名指しの台帳::生成する(領域);
        let mut 辿る状態の台帳 = 辿る状態の台帳::生成する(領域);
        let mut 初期状態一覧 = Vec::new();
        for 状態 in 初期状態の数え上げ.試す値一覧() {
            初期状態一覧.push(名指しの台帳.状態を名指す(状態));
            辿る状態の台帳.初めて見た状態なら控える(状態.clone());
        }
        Self {
            領域,
            上限,
            辿る状態の台帳,
            名指しの台帳,
            初期状態一覧,
            遷移一覧: Vec::new(),
            網羅性の根拠,
        }
    }

    /// 待ち行列が空になるまで辿る。控えた状態が上限を超えた時点で打ち切り、打ち切ったことを網羅性へ残す。
    pub(super) fn 初期状態から辿る(&mut self) {
        while let Some(いま) = self.辿る状態の台帳.次に辿る状態を取り出す() {
            if self.辿る状態の台帳.控えた代表の件数() > self.上限.状態の件数() {
                self.網羅性の根拠.上限で打ち切ったと記す(self.上限);
                return;
            }
            self.状態1つから遷移を組む(&いま);
        }
    }

    /// 組んだ遷移モデルと網羅性から探索が組んだ遷移モデルと網羅性を組み立てる。2つの台帳が数えた、異なる状態に同じ同一性を与えたことと
    /// 異なる値に同じ名指しを与えたことを網羅性の根拠へ渡し、根拠に網羅性を決めさせる。
    pub(super) fn 遷移モデルと網羅性を組み立てる(self) -> 探索が組んだ遷移モデルと網羅性 {
        let mut 網羅性の根拠 = self.網羅性の根拠;
        網羅性の根拠.別の状態と同じ同一性を与えられた状態の名前を記録する(self.辿る状態の台帳.別の状態と同じ同一性を与えられた状態の名前一覧へ渡す());
        網羅性の根拠.異なる値に与えられた名指しの表記を記録する(self.名指しの台帳.異なる値に与えられた名指しの表記一覧へ渡す());
        探索が組んだ遷移モデルと網羅性 {
            モデル: 遷移モデル::生成する(self.初期状態一覧, self.遷移一覧),
            網羅性: 網羅性の根拠.網羅性を決める(),
        }
    }

    fn 状態1つから遷移を組む(&mut self, いま: &領域型::状態) {
        let 数え上げ: 数え上げ<領域型::コマンド> = self.領域.状態で試すコマンドを数え上げる(いま);
        self.網羅性の根拠.連続量の説明を控える(数え上げ.連続量の説明());
        for コマンド in 数え上げ.試す値一覧() {
            self.遷移1回を取り込む(いま, コマンド);
        }
    }

    fn 遷移1回を取り込む(&mut self, 前の状態: &領域型::状態, コマンド: &領域型::コマンド) {
        let 材料 = self.遷移の材料を組む(前の状態, コマンド);
        match self.領域.一回遷移する(前の状態, コマンド) {
            遷移の帰結::成功 { 次の状態, 出来事一覧 } => {
                let 後状態 = self.名指しの台帳.状態を名指す(&次の状態);
                let mut 出来事の参照一覧 = Vec::new();
                for 出来事 in &出来事一覧 {
                    出来事の参照一覧.push(self.名指しの台帳.出来事を名指す(出来事));
                }
                self.遷移一覧.push(遷移::成功として生成する(材料, 後状態, 出来事の参照一覧));
                self.辿る状態の台帳.初めて見た状態なら控える(次の状態);
            }
            遷移の帰結::失敗 { 説明 } => {
                let 失敗 = 失敗した遷移の節点を組む(&材料, &説明);
                self.遷移一覧.push(遷移::失敗として生成する(材料, 失敗));
            }
        }
    }

    /// 遷移1件の材料を組む。識別子が前状態と入力をそのまま持つのは、同じ組から2件の遷移が出ないことを、
    /// 2つの表記を1本へ繋いだ文字列ではなく組そのもので保つためである。
    fn 遷移の材料を組む(&mut self, 前の状態: &領域型::状態, コマンド: &領域型::コマンド) -> 遷移の材料 {
        let 前状態 = self.名指しの台帳.状態を名指す(前の状態);
        let 入力 = self.名指しの台帳.コマンドを名指す(コマンド);
        遷移の材料 {
            識別子: 遷移の識別子::前状態と入力から生成する(前状態, 入力),
            適用した規則: self.領域.規則を名指す(),
        }
    }
}

/// 失敗した遷移を表す節点を組む。人が読む説明文だけを名前にしないのは、同じ文面で失敗する別の遷移が1つの節点へ1つにまとめられ、
/// 検証がその2件を同じ失敗として読むためである。所有者は前状態と入力の全成分を保存し、名前は説明だけを持つ。
/// 探索のフィールドを1つも読まないため自由関数で持つ(参照: グローバルCLAUDE.md「Rustの書き方の選択」条5(a))。
fn 失敗した遷移の節点を組む(材料: &遷移の材料, 説明: &str) -> 設計概念への参照 {
    設計概念への参照::実行時のドメイン概念として生成する(遷移が失敗した節点の名前の空間, 説明).所有者を添える(材料.識別子.所有者の並びへ写す())
}
