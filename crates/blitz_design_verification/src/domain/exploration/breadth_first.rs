//! 領域を初期状態から幅優先で辿り、実物の遷移関数を呼んで遷移モデルを組む探索。
//!
//! 辿る状態の台帳・組んだ遷移の並び・連続量の説明の蓄積・上限に達したかの4つを探索自身が所有する。
//! これらを引数で引き回すと、辿る工程を1つ足すたびに全部の署名へ足すことになり、どの工程がどれを変えるかが読めなくなる。
//! 探索は領域を借りるだけであり、状態の中身を1つも解釈しない(解釈するのは領域の側の `状態の同一性を答える` と `状態を名指す` である)。
//!
//! **済みの集合の鍵は `状態の同一性を答える` の答えであり、`状態を名指す` の名前ではない。** 名前は表示のために丸めてよく、
//! 丸めた名前を鍵にすると別の状態が黙って同じ1件として捨てられる。同一性も領域が書く以上、異なる状態を同じ値へ写す実装は書ける。
//! 書けること自体は止められないため、**この探索は同一性ごとに代表の状態を持ち、代表と等しくない状態が同じ同一性へ写った事実を記録し、
//! その数え上げに `全件を数え上げた` を名乗らせない**。嘘をつける口を残したまま、嘘をついた結果が全件を名乗れないようにする形である。

use super::super::{数え上げ, 有限に数え上げられる領域, 遷移の帰結};
use super::state_ledger::辿る状態の台帳;
use super::{探索の上限, 探索の結末};
use crate::{数え上げの網羅性, 設計概念への参照, 遷移, 遷移の材料, 遷移の識別子, 遷移モデル};

// 遷移が失敗したことを表す節点の名前の空間。領域が名指すドメインの概念と同じ空間へ入れないのは、
// 失敗の節点が探索の側で組む名前であり、実在の概念の名前と衝突させないためである。
const 遷移が失敗した節点の名前の空間: &str = "設計の検証の探索";

pub(super) struct 幅優先の探索<'領域, 領域型: 有限に数え上げられる領域> {
    領域: &'領域 領域型,
    上限: 探索の上限,
    台帳: 辿る状態の台帳<'領域, 領域型>,
    初期状態一覧: Vec<設計概念への参照>,
    遷移一覧: Vec<遷移>,
    連続量の説明一覧: Vec<String>, // 同じ文は1度だけ残す
    上限で打ち切ったか: bool,
}

impl<'領域, 領域型: 有限に数え上げられる領域> 幅優先の探索<'領域, 領域型> {
    pub(super) fn 生成する(領域: &'領域 領域型, 上限: 探索の上限) -> Self {
        let 初期状態 = 領域.初期状態一覧();
        let mut 探索 = Self {
            領域,
            上限,
            台帳: 辿る状態の台帳::生成する(領域),
            初期状態一覧: 初期状態.iter().map(|状態| 領域.状態を名指す(状態)).collect(),
            遷移一覧: Vec::new(),
            連続量の説明一覧: Vec::new(),
            上限で打ち切ったか: false,
        };
        for 状態 in 初期状態 {
            探索.台帳.初めて見た状態なら控える(状態);
        }
        探索
    }

    /// 待ち行列が空になるまで辿る。控えた状態が上限を超えた時点で打ち切り、打ち切ったことを網羅性へ残す。
    pub(super) fn 初期状態から辿る(&mut self) {
        while let Some(いま) = self.台帳.次に辿る状態を取り出す() {
            if self.台帳.控えた代表の件数() > self.上限.状態の件数() {
                self.上限で打ち切ったか = true;
                return;
            }
            self.状態1つから遷移を組む(&いま);
        }
    }

    /// 組んだ遷移モデルと網羅性へ畳む。畳みを最も優先するのは、畳みが起きた探索では領域の答えた同一性そのものが状態を区別できておらず、
    /// 辿らなかった状態が在ることを件数からも上限からも読めないためである。上限で打ち切ったことを連続量の標本より優先するのは、
    /// 打ち切った先を1件も見ていないためである。
    pub(super) fn 結末へ畳む(self) -> 探索の結末 {
        let 畳まれた状態の名前一覧 = self.台帳.畳まれた状態の名前一覧へ渡す();
        let 網羅性 = if !畳まれた状態の名前一覧.is_empty() {
            数え上げの網羅性::異なる状態を同じ同一性へ畳んだ { 畳まれた状態の名前一覧 }
        } else if self.上限で打ち切ったか {
            数え上げの網羅性::上限で打ち切った { 上限: self.上限.状態の件数() }
        } else if self.連続量の説明一覧.is_empty() {
            数え上げの網羅性::全件を数え上げた
        } else {
            数え上げの網羅性::連続量の標本に限る { 説明一覧: self.連続量の説明一覧 }
        };
        探索の結末 {
            モデル: 遷移モデル::生成する(self.初期状態一覧, self.遷移一覧),
            網羅性,
        }
    }

    fn 状態1つから遷移を組む(&mut self, いま: &領域型::状態) {
        let 数え上げ: 数え上げ<領域型::コマンド> = self.領域.状態で試すコマンドを数え上げる(いま);
        if let Some(説明) = 数え上げ.連続量の説明() {
            let 文 = 説明.to_string();
            if !self.連続量の説明一覧.contains(&文) {
                self.連続量の説明一覧.push(文);
            }
        }
        for コマンド in 数え上げ.試す値一覧() {
            self.遷移1回を取り込む(いま, コマンド);
        }
    }

    fn 遷移1回を取り込む(&mut self, 前の状態: &領域型::状態, コマンド: &領域型::コマンド) {
        let 材料 = self.遷移の材料を組む(前の状態, コマンド);
        match self.領域.一回遷移する(前の状態, コマンド) {
            遷移の帰結::成功 { 次の状態, 出来事一覧 } => {
                let 後状態 = self.領域.状態を名指す(&次の状態);
                let 出来事の参照一覧 = 出来事一覧.iter().map(|出来事| self.領域.出来事を名指す(出来事)).collect();
                self.遷移一覧.push(遷移::成功として生成する(材料, 後状態, 出来事の参照一覧));
                self.台帳.初めて見た状態なら控える(次の状態);
            }
            遷移の帰結::失敗 { 説明 } => {
                let 失敗 = self.失敗した遷移の節点を組む(&材料, &説明);
                self.遷移一覧.push(遷移::失敗として生成する(材料, 失敗));
            }
        }
    }

    /// 失敗した遷移を表す節点を組む。人が読む説明文だけを名前にしないのは、同じ文面で失敗する別の遷移が1つの節点へ畳まれ、
    /// 検証がその2件を同じ失敗として読むためである。名前へ遷移の識別子を入れることで、失敗の節点は遷移1件ごとに別になる。
    fn 失敗した遷移の節点を組む(&self, 材料: &遷移の材料, 説明: &str) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(遷移が失敗した節点の名前の空間, &format!("{}の遷移失敗結果({説明})", 材料.識別子.表記()))
    }

    /// 遷移1件の材料を組む。識別子を前状態とコマンドの表記から綴るのは、同じ組から2件の遷移が出ないためである。
    fn 遷移の材料を組む(&self, 前の状態: &領域型::状態, コマンド: &領域型::コマンド) -> 遷移の材料 {
        let 前状態 = self.領域.状態を名指す(前の状態);
        let 入力 = self.領域.コマンドを名指す(コマンド);
        遷移の材料 {
            識別子: 遷移の識別子::生成する(&format!("{}へ{}を与えた遷移", 前状態.表記(), 入力.表記())),
            前状態,
            入力,
            適用した規則: self.領域.規則を名指す(),
        }
    }
}
