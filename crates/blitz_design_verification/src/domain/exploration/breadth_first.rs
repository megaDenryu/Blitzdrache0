//! 領域を初期状態から幅優先で辿り、実物の遷移関数を呼んで遷移モデルを組む探索。
//!
//! 待ち行列・名指した状態の集合・組んだ遷移の並び・連続量の説明の蓄積・上限に達したかの5つを探索自身が所有する。
//! これらを引数で引き回すと、辿る工程を1つ足すたびに全部の署名へ足すことになり、どの工程がどれを変えるかが読めなくなる。
//! 探索は領域を借りるだけであり、状態の中身を1つも解釈しない(解釈するのは領域の側の `状態を名指す` である)。

use std::collections::{HashSet, VecDeque};

use super::super::{数え上げ, 有限に数え上げられる領域, 遷移の帰結};
use super::{探索の上限, 探索の結末};
use crate::{数え上げの網羅性, 設計概念の識別子, 遷移, 遷移の材料, 遷移の識別子, 遷移モデル};

pub(super) struct 幅優先の探索<'領域, 領域型: 有限に数え上げられる領域> {
    領域: &'領域 領域型,
    上限: 探索の上限,
    待ち: VecDeque<領域型::状態>,
    名指した状態: HashSet<設計概念の識別子>, // 同じ識別子へ写る状態を2度辿らないための済みの集合
    初期状態一覧: Vec<設計概念の識別子>,
    遷移一覧: Vec<遷移>,
    連続量の説明一覧: Vec<String>, // 同じ文は1度だけ残す
    上限で打ち切ったか: bool,
}

impl<'領域, 領域型: 有限に数え上げられる領域> 幅優先の探索<'領域, 領域型> {
    pub(super) fn 生成する(領域: &'領域 領域型, 上限: 探索の上限) -> Self {
        let 初期状態 = 領域.初期状態一覧();
        let 初期状態一覧: Vec<設計概念の識別子> = 初期状態.iter().map(|状態| 領域.状態を名指す(状態)).collect();
        Self {
            領域,
            上限,
            待ち: VecDeque::from(初期状態),
            名指した状態: 初期状態一覧.iter().cloned().collect(),
            初期状態一覧,
            遷移一覧: Vec::new(),
            連続量の説明一覧: Vec::new(),
            上限で打ち切ったか: false,
        }
    }

    /// 待ち行列が空になるまで辿る。名指した状態が上限を超えた時点で打ち切り、打ち切ったことを網羅性へ残す。
    pub(super) fn 初期状態から辿る(&mut self) {
        while let Some(いま) = self.待ち.pop_front() {
            if self.名指した状態.len() > self.上限.状態の件数() {
                self.上限で打ち切ったか = true;
                return;
            }
            self.状態1つから遷移を組む(&いま);
        }
    }

    /// 組んだ遷移モデルと網羅性へ畳む。上限で打ち切ったことを連続量の標本より優先するのは、
    /// 打ち切った先を1件も見ていないためである。
    pub(super) fn 結末へ畳む(self) -> 探索の結末 {
        let 網羅性 = if self.上限で打ち切ったか {
            数え上げの網羅性::上限で打ち切った { 上限: self.上限.状態の件数() }
        } else if self.連続量の説明一覧.is_empty() {
            数え上げの網羅性::全件を数え上げた
        } else {
            数え上げの網羅性::連続量の標本に限る { 説明一覧: self.連続量の説明一覧 }
        };
        探索の結末 {
            モデル: 遷移モデル::生成する(self.初期状態一覧, self.遷移一覧),
            網羅性,
        }
    }

    fn 状態1つから遷移を組む(&mut self, いま: &領域型::状態) {
        let 数え上げ: 数え上げ<領域型::コマンド> = self.領域.状態で試すコマンドを数え上げる(いま);
        if let Some(説明) = 数え上げ.連続量の説明() {
            let 文 = 説明.to_string();
            if !self.連続量の説明一覧.contains(&文) {
                self.連続量の説明一覧.push(文);
            }
        }
        for コマンド in 数え上げ.試す値一覧() {
            self.遷移1回を取り込む(いま, コマンド);
        }
    }

    fn 遷移1回を取り込む(&mut self, 前の状態: &領域型::状態, コマンド: &領域型::コマンド) {
        let 材料 = self.遷移の材料を組む(前の状態, コマンド);
        match self.領域.一回遷移する(前の状態, コマンド) {
            遷移の帰結::成功 { 次の状態, 出来事一覧 } => {
                let 後状態 = self.領域.状態を名指す(&次の状態);
                let 出来事の識別子一覧 = 出来事一覧.iter().map(|出来事| self.領域.出来事を名指す(出来事)).collect();
                self.遷移一覧.push(遷移::成功として生成する(材料, 後状態.clone(), 出来事の識別子一覧));
                if self.名指した状態.insert(後状態) {
                    self.待ち.push_back(次の状態);
                }
            }
            遷移の帰結::失敗 { 説明 } => {
                let 失敗 = 設計概念の識別子::実行時のドメイン概念として生成する("", &format!("遷移の失敗({説明})"));
                self.遷移一覧.push(遷移::失敗として生成する(材料, 失敗));
            }
        }
    }

    /// 遷移1件の材料を組む。識別子を前状態とコマンドの表記から綴るのは、同じ組から2件の遷移が出ないためである。
    fn 遷移の材料を組む(&self, 前の状態: &領域型::状態, コマンド: &領域型::コマンド) -> 遷移の材料 {
        let 前状態 = self.領域.状態を名指す(前の状態);
        let 入力 = self.領域.コマンドを名指す(コマンド);
        遷移の材料 {
            識別子: 遷移の識別子::生成する(&format!("{}へ{}を与えた遷移", 前状態.表記(), 入力.表記())),
            前状態,
            入力,
            適用した規則: self.領域.規則を名指す(),
        }
    }
}
