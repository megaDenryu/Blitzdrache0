//! 状態遷移失敗結果の元の状態の食い違いと、それを数える元の状態の照合。
//!
//! 状態遷移失敗結果の元の状態の食い違いとは、探索が実物の状態遷移関数を呼んで失敗した状態遷移のうち、状態遷移失敗結果に入れて返した元の状態が、
//! 状態遷移の受け取った状態と等しくなかったものの並びのことである。
//!
//! 状態遷移は状態を値で受け取り、失敗のとき受け取った状態を書き換えずに返す(設計オントロジー 3.5.9)。型が保証するのは状態を返す口があることまでであり、
//! 返した値が受け取った値と等しいことは型では保証されない。探索はすべての失敗した状態遷移でこの等しさを確かめ、食い違いが1件でもあれば
//! 状態遷移モデルを返さずこの値を返す。状態遷移関数の契約を破った領域から組んだモデルで命題を答えると、答えの根拠が壊れた状態遷移関数になるためである。

use std::fmt;

use crate::状態遷移の識別子;

/// 失敗した状態遷移のうち、元の状態を受け取った状態と異なる値で返したものの並び。探索がこれを返すとき、状態遷移モデルは返らない。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 状態遷移失敗結果の元の状態の食い違い {
    食い違った状態遷移一覧: Vec<状態遷移の識別子>,
}

/// 元の状態の照合とは、探索が失敗した状態遷移ごとに、帰結の元の状態と状態遷移の受け取った状態を比べ、食い違った状態遷移を控える台帳のことである。
pub(super) struct 元の状態の照合 {
    食い違った状態遷移一覧: Vec<状態遷移の識別子>,
}

impl 元の状態の照合 {
    pub(super) fn 生成する() -> Self {
        Self { 食い違った状態遷移一覧: Vec::new() }
    }

    /// 失敗した状態遷移1件の元の状態を、状態遷移の受け取った状態と比べる。等しくなければその状態遷移を控える。
    pub(super) fn 失敗した状態遷移を照合する<状態: PartialEq>(&mut self, 状態遷移: &状態遷移の識別子, 元の状態: &状態, 受け取った状態: &状態) {
        if 元の状態 != 受け取った状態 {
            self.食い違った状態遷移一覧.push(状態遷移.clone());
        }
    }

    /// 食い違った状態遷移が1件も無ければ成功を、あれば食い違いを返す。
    pub(super) fn 食い違いが無いことを確かめる(self) -> Result<(), 状態遷移失敗結果の元の状態の食い違い> {
        if self.食い違った状態遷移一覧.is_empty() {
            return Ok(());
        }
        Err(状態遷移失敗結果の元の状態の食い違い {
            食い違った状態遷移一覧: self.食い違った状態遷移一覧,
        })
    }
}

impl 状態遷移失敗結果の元の状態の食い違い {
    /// 元の状態を受け取った状態と異なる値で返した状態遷移の並び。探索がたどった順である。
    pub fn 食い違った状態遷移一覧(&self) -> &[状態遷移の識別子] {
        &self.食い違った状態遷移一覧
    }
}

impl fmt::Display for 状態遷移失敗結果の元の状態の食い違い {
    fn fmt(&self, 書き先: &mut fmt::Formatter<'_>) -> fmt::Result {
        let 表記一覧: Vec<String> = self.食い違った状態遷移一覧.iter().map(状態遷移の識別子::表記).collect();
        write!(
            書き先,
            "失敗した状態遷移{}件が、状態遷移失敗結果の元の状態へ状態遷移の受け取った状態と異なる値を入れて返した(失敗のとき状態遷移は受け取った状態を書き換えずに返さなければならない。設計オントロジー 3.5.9): {}",
            self.食い違った状態遷移一覧.len(),
            表記一覧.join(" / ")
        )
    }
}

impl std::error::Error for 状態遷移失敗結果の元の状態の食い違い {}
