//! 遷移失敗結果の元の状態の食い違いと、それを数える元の状態の照合。
//!
//! 遷移失敗結果の元の状態の食い違いとは、探索が実物の遷移関数を呼んで失敗した遷移のうち、遷移失敗結果に入れて返した元の状態が、
//! 遷移の受け取った状態と等しくなかったものの並びのことである。
//!
//! 遷移は状態を値で受け取り、失敗のとき受け取った状態を書き換えずに返す(設計オントロジー 3.5.9)。型が保証するのは状態を返す口があることまでであり、
//! 返した値が受け取った値と等しいことは型では保証されない。探索はすべての失敗した遷移でこの等しさを確かめ、食い違いが1件でもあれば
//! 遷移モデルを返さずこの値を返す。遷移関数の契約を破った領域から組んだモデルで命題を答えると、答えの根拠が壊れた遷移関数になるためである。

use std::fmt;

use crate::遷移の識別子;

/// 失敗した遷移のうち、元の状態を受け取った状態と異なる値で返したものの並び。探索がこれを返すとき、遷移モデルは返らない。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 遷移失敗結果の元の状態の食い違い {
    食い違った遷移一覧: Vec<遷移の識別子>,
}

/// 元の状態の照合とは、探索が失敗した遷移ごとに、帰結の元の状態と遷移の受け取った状態を比べ、食い違った遷移を控える台帳のことである。
pub(super) struct 元の状態の照合 {
    食い違った遷移一覧: Vec<遷移の識別子>,
}

impl 元の状態の照合 {
    pub(super) fn 生成する() -> Self {
        Self { 食い違った遷移一覧: Vec::new() }
    }

    /// 失敗した遷移1件の元の状態を、遷移の受け取った状態と比べる。等しくなければその遷移を控える。
    pub(super) fn 失敗した遷移を照合する<状態: PartialEq>(&mut self, 遷移: &遷移の識別子, 元の状態: &状態, 受け取った状態: &状態) {
        if 元の状態 != 受け取った状態 {
            self.食い違った遷移一覧.push(遷移.clone());
        }
    }

    /// 食い違った遷移が1件も無ければ成功を、あれば食い違いを返す。
    pub(super) fn 食い違いが無いことを確かめる(self) -> Result<(), 遷移失敗結果の元の状態の食い違い> {
        if self.食い違った遷移一覧.is_empty() {
            return Ok(());
        }
        Err(遷移失敗結果の元の状態の食い違い {
            食い違った遷移一覧: self.食い違った遷移一覧
        })
    }
}

impl 遷移失敗結果の元の状態の食い違い {
    /// 元の状態を受け取った状態と異なる値で返した遷移の並び。探索がたどった順である。
    pub fn 食い違った遷移一覧(&self) -> &[遷移の識別子] {
        &self.食い違った遷移一覧
    }
}

impl fmt::Display for 遷移失敗結果の元の状態の食い違い {
    fn fmt(&self, 書き先: &mut fmt::Formatter<'_>) -> fmt::Result {
        let 表記一覧: Vec<String> = self.食い違った遷移一覧.iter().map(遷移の識別子::表記).collect();
        write!(
            書き先,
            "失敗した遷移{}件が、遷移失敗結果の元の状態へ遷移の受け取った状態と異なる値を入れて返した(失敗のとき遷移は受け取った状態を書き換えずに返さなければならない。設計オントロジー 3.5.9): {}",
            self.食い違った遷移一覧.len(),
            表記一覧.join(" / ")
        )
    }
}

impl std::error::Error for 遷移失敗結果の元の状態の食い違い {}
