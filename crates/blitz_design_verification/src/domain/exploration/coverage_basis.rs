//! 探索が数え上げの網羅性を名乗る根拠。見た範囲の限りを覚え、最後に網羅性を1つ答える。
//!
//! 探索の側へ平らに置かず1つの型にするのは、限りを記すメソッドと網羅性を決めるメソッドが1箇所へ揃い、
//! 限りを1つ足すときに、記すメソッドと優先順位の両方を同じファイルで直せるためである。
//! 探索が持つ他の3つ(辿る状態の台帳・名指しの台帳・組んだ遷移の並び)とはフィールドを共有しない。

use super::探索の上限;
use crate::数え上げの網羅性;

/// 数え上げの網羅性の根拠とは、探索が見た範囲の限りを覚え、そこから網羅性を1つ答える台帳のことである。
pub(super) struct 数え上げの網羅性の根拠 {
    重複と判定された状態の名前一覧: Vec<String>,
    重複と判定された名指しの表記一覧: Vec<String>,
    打ち切った上限: Option<探索の上限>,
    連続量の説明一覧: Vec<String>, // 同じ文は1度だけ残す
}

impl 数え上げの網羅性の根拠 {
    /// 限りを1つも記していない根拠を組む。このまま決めれば全件を数え上げたになる。
    pub(super) fn 生成する() -> Self {
        Self {
            重複と判定された状態の名前一覧: Vec::new(),
            重複と判定された名指しの表記一覧: Vec::new(),
            打ち切った上限: None,
            連続量の説明一覧: Vec::new(),
        }
    }

    /// 数え上げが名乗った連続量の説明を控える。同じ文は1度だけ残す。
    pub(super) fn 連続量の説明を控える(&mut self, 説明: Option<&str>) {
        let Some(文) = 説明.map(str::to_string) else {
            return;
        };
        if !self.連続量の説明一覧.contains(&文) {
            self.連続量の説明一覧.push(文);
        }
    }

    /// 探索してよい状態の件数の上限に達して打ち切ったことを記す。
    pub(super) fn 上限で打ち切ったと記す(&mut self, 上限: 探索の上限) {
        self.打ち切った上限 = Some(上限);
    }

    /// 辿る状態の台帳が数えた、重複と判定された状態の名前を記録する。
    pub(super) fn 重複と判定された状態の名前を記録する(&mut self, 重複と判定された状態の名前一覧: Vec<String>) {
        self.重複と判定された状態の名前一覧 = 重複と判定された状態の名前一覧;
    }

    /// 名指しの台帳が数えた、重複と判定された名指しの表記を記録する。
    pub(super) fn 重複と判定された名指しの表記を記録する(&mut self, 重複と判定された名指しの表記一覧: Vec<String>) {
        self.重複と判定された名指しの表記一覧 = 重複と判定された名指しの表記一覧;
    }

    /// 記した限りから網羅性を1つ決める。状態の同一性の重複を最も優先するのは、そこでは辿らなかった状態が在ることを
    /// 件数からも上限からも読めないためである。名指しの重複を次に置くのは、辿りは足りていてもモデルの上で
    /// 互いに等しくない2つの値が1件の節点へ重なり、命題の層がその2つを区別できないためである。
    /// 上限で打ち切ったことを連続量の標本より優先するのは、打ち切った先を1件も見ていないためである。
    pub(super) fn 網羅性を決める(self) -> 数え上げの網羅性 {
        if !self.重複と判定された状態の名前一覧.is_empty() {
            return 数え上げの網羅性::異なる状態に同じ同一性を与えた {
                重複と判定された状態の名前一覧: self.重複と判定された状態の名前一覧,
            };
        }
        if !self.重複と判定された名指しの表記一覧.is_empty() {
            return 数え上げの網羅性::異なる値に同じ名指しを与えた {
                重複と判定された名指しの表記一覧: self.重複と判定された名指しの表記一覧,
            };
        }
        if let Some(上限) = self.打ち切った上限 {
            return 数え上げの網羅性::上限で打ち切った { 上限: 上限.状態の件数() };
        }
        if self.連続量の説明一覧.is_empty() {
            return 数え上げの網羅性::全件を数え上げた;
        }
        数え上げの網羅性::連続量の標本に限る { 説明一覧: self.連続量の説明一覧 }
    }
}
