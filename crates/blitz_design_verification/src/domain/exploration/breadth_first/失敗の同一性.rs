//! 同じ表示を持つ別の状態や入力が、失敗のノードを共有しないことを固定する。

use super::失敗した状態遷移のノードを組む;
use crate::{状態遷移の材料, 状態遷移の識別子, 設計概念の識別用情報};

#[test]
fn 状態と入力の識別用情報が違えば失敗のノードも違う() {
    let 状態 = 設計概念の識別用情報::型として生成する("題材", "状態");
    let 別種類の状態 = 設計概念の識別用情報::トレイトとして生成する("題材", "状態");
    let 入力 = 設計概念の識別用情報::型として生成する("題材", "入力");
    let 別種類の入力 = 設計概念の識別用情報::トレイトとして生成する("題材", "入力");
    assert_eq!(状態.表記(), 別種類の状態.表記());
    assert_eq!(入力.表記(), 別種類の入力.表記());
    let 材料 = |状態, 入力| 状態遷移の材料::生成する(状態遷移の識別子::前状態と入力から生成する(状態, 入力), 設計概念の識別用情報::型として生成する("題材", "規則"));
    let 甲 = 失敗した状態遷移のノードを組む(&材料(状態.clone(), 入力.clone()), "失敗");
    let 乙 = 失敗した状態遷移のノードを組む(&材料(別種類の状態, 入力.clone()), "失敗");
    let 丙 = 失敗した状態遷移のノードを組む(&材料(状態, 別種類の入力), "失敗");
    assert_ne!(甲, 乙);
    assert_ne!(甲, 丙);
}
