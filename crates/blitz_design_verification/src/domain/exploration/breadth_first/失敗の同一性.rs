//! 同じ表示を持つ別の状態や入力が、失敗の節点を共有しないことを固定する。

use super::失敗した遷移の節点を組む;
use crate::{設計概念への参照, 遷移の材料, 遷移の識別子};

#[test]
fn 状態と入力の参照が違えば失敗の節点も違う() {
    let 状態 = 設計概念への参照::型として生成する("題材", "状態");
    let 別種類の状態 = 設計概念への参照::トレイトとして生成する("題材", "状態");
    let 入力 = 設計概念への参照::型として生成する("題材", "入力");
    let 別種類の入力 = 設計概念への参照::トレイトとして生成する("題材", "入力");
    assert_eq!(状態.表記(), 別種類の状態.表記());
    assert_eq!(入力.表記(), 別種類の入力.表記());
    let 材料 = |状態, 入力| 遷移の材料 {
        識別子: 遷移の識別子::前状態と入力から生成する(状態, 入力),
        適用した規則: 設計概念への参照::型として生成する("題材", "規則"),
    };
    let 甲 = 失敗した遷移の節点を組む(&材料(状態.clone(), 入力.clone()), "失敗");
    let 乙 = 失敗した遷移の節点を組む(&材料(別種類の状態, 入力.clone()), "失敗");
    let 丙 = 失敗した遷移の節点を組む(&材料(状態, 別種類の入力), "失敗");
    assert_ne!(甲, 乙);
    assert_ne!(甲, 丙);
}
