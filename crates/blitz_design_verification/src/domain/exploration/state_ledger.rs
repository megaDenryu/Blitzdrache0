//! 探索が辿る状態の台帳。状態の同一性ごとに代表の状態を控え、まだ辿っていない状態を待たせ、
//! 代表と等しくない状態が同じ同一性へ写った事実を残す。
//!
//! 幅優先の探索から分けるのは、この3つ(代表の控え・待ちの順番・重複としてまとめた事実)が1つの不変条件を共有するためである。
//! その不変条件とは、1つの同一性につき代表は1件だけであり、その代表と等しくない状態がその同一性へ写ったなら必ず記録が残る、である。
//! 探索の側へ平らに置くと、待ち行列へ入れる判断と重複のまとめを数える判断が別々の場所で書かれ、片方だけ書き忘れても型が通る。

use std::collections::hash_map::Entry;
use std::collections::{HashMap, VecDeque};

use super::super::有限に数え上げられる領域;

pub(super) struct 辿る状態の台帳<'領域, 領域型: 有限に数え上げられる領域> {
    領域: &'領域 領域型,
    待ち: VecDeque<領域型::状態>,
    同一性ごとの代表の状態: HashMap<領域型::状態の同一性, 領域型::状態>,
    重複と判定された状態の名前一覧: Vec<String>, // 同じ名前は1度だけ残す
}

impl<'領域, 領域型: 有限に数え上げられる領域> 辿る状態の台帳<'領域, 領域型> {
    pub(super) fn 生成する(領域: &'領域 領域型) -> Self {
        Self {
            領域,
            待ち: VecDeque::new(),
            同一性ごとの代表の状態: HashMap::new(),
            重複と判定された状態の名前一覧: Vec::new(),
        }
    }

    /// 同一性で見て初めての状態なら代表として控え、待ちへ加える。既に代表が居る同一性へ代表と等しくない状態が写ったなら、
    /// その状態の名前を重複としてまとめた事実として残す。重複としてまとめた状態を待ちへ加えないのは、同一性が一致する限り辿り直しても終わらないためである。
    pub(super) fn 初めて見た状態なら控える(&mut self, 状態: 領域型::状態) {
        let 領域 = self.領域;
        match self.同一性ごとの代表の状態.entry(領域.状態の同一性を答える(&状態)) {
            Entry::Vacant(空き) => {
                空き.insert(状態.clone());
                self.待ち.push_back(状態);
            }
            Entry::Occupied(代表) => {
                if 代表.get() != &状態 {
                    let 名前 = 領域.状態を名指す(&状態).表記();
                    if !self.重複と判定された状態の名前一覧.contains(&名前) {
                        self.重複と判定された状態の名前一覧.push(名前);
                    }
                }
            }
        }
    }

    /// まだ辿っていない状態を1件取り出す。無ければ値なしである。
    pub(super) fn 次に辿る状態を取り出す(&mut self) -> Option<領域型::状態> {
        self.待ち.pop_front()
    }

    /// これまでに控えた代表の件数。探索の上限はこの件数で判断する。
    pub(super) fn 控えた代表の件数(&self) -> usize {
        self.同一性ごとの代表の状態.len()
    }

    /// 代表と等しくない状態が同じ同一性へ写った事実の並び。空なら重複のまとめは1度も起きていない。
    pub(super) fn 重複と判定された状態の名前一覧へ渡す(self) -> Vec<String> {
        self.重複と判定された状態の名前一覧
    }
}
