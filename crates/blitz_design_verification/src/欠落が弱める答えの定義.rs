//! 欠落が弱める答えとは、抽出が事実を落としたために、グラフへの問いが辺か分類の事実の不在を根拠にして答えられなくなった答えの種類のことである。
//! 答えの種類は、設計関係の種類ごとの在り方・プリミティブな関係の種類ごとの在り方・分類の3つに分かれる。
//!
//! この型が在るのは、欠落の弱め方を関係の種類ごとに絞るためである。欠落を1つの真偽で持つと、関数の署名の型の表記を読めなかった欠けが、
//! その欠けと無関係な別の種類のプリミティブな関係や設計関係の答えまで未決定へ倒す。
//! 参照: `_doc/設計/設計オントロジー.md` 第9節。

use crate::{プリミティブな関係の種類, 設計関係の種類, 頭の関係};

/// 欠落が不在を根拠にできなくする答えの種類。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 欠落が弱める答え {
    /// その種類の設計関係が在るか・その種類の辺を辿る経路が在るか。
    設計関係(設計関係の種類),
    /// その種類のプリミティブな関係が在るか・その種類の辺を辿る経路が在るか。
    プリミティブな関係(プリミティブな関係の種類),
    /// 概念の分類が設計解釈マーカーを含むか。
    分類,
}

impl 欠落が弱める答え {
    /// 全ての答え。モジュールを丸ごと読めなかった欠けと同一性の衝突は、どの答えの根拠も奪うためこの並びを弱める。
    pub fn 全部() -> Vec<Self> {
        let プリミティブ = プリミティブな関係の種類::全部().map(Self::プリミティブな関係);
        Self::全ての設計関係().into_iter().chain(プリミティブ).chain([Self::分類]).collect()
    }

    /// 全ての種類の設計関係の答え。`設計関係へ1つも参加していない` はプリミティブな関係と分類を参加に数えないため、この並びだけに依る。
    pub fn 全ての設計関係() -> [Self; 4] {
        設計関係の種類::最小語彙().map(Self::設計関係)
    }

    /// 定義の式の規則の頭の関係が、その規則が導けなかったときに弱める答え。
    pub const fn 規則の頭から求める(頭: 頭の関係) -> Self {
        match 頭 {
            頭の関係::設計関係(種類) => Self::設計関係(種類),
            頭の関係::プリミティブな関係(種類) => Self::プリミティブな関係(種類),
        }
    }

    /// 人が読む語。未決定の理由の説明がこの語で、どの答えを弱めたかを示す。
    pub const fn 語(self) -> &'static str {
        match self {
            Self::設計関係(種類) => 種類.語(),
            Self::プリミティブな関係(種類) => 種類.語(),
            Self::分類 => "分類",
        }
    }
}
