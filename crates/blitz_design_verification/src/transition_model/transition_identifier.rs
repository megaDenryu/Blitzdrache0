//! 遷移の識別子とは、遷移モデルの中で1件の遷移を名指す、前状態と入力の組のことである。
//!
//! **前状態と入力を1本の文字列へ連結しない。** 連結した表記から識別子を組むと、`{前状態}へ{入力}を与えた遷移` のような
//! 書き方では、区切りの語が名前の中に現れた別の組が同じ1本の文字列になる。そうなると別の遷移が命題の層で同じ1件として
//! 引き当てられ、Bしか起きていないのに `発生する(A)` が通る。2つを別のフィールドで持てばこの紛れは起こらない。
//!
//! 命題の項は設計概念への参照しか取らないため、項へ入れる境界でこの識別子を参照へ写す。そこでも1本へ連結せず、
//! 参照が既に持つ所有者の並びへ、前状態と入力の全成分を長さ付きで符号化して入れる。
//! 参照: `_doc/設計/設計オントロジー.md` 第9節。

use crate::設計概念への参照;

// 遷移を表す節点の名前の空間。ドメインが名指す状態・入力と同じ空間へ入れないのは、遷移が探索の側で組む概念であるためである。
const 遷移の名前の空間: &str = "設計の検証の遷移";

/// 遷移モデルの中で1件の遷移を名指す識別子。前状態と入力の2つをそのまま持つ。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct 遷移の識別子 {
    前状態: 設計概念への参照,
    入力: 設計概念への参照,
}

impl 遷移の識別子 {
    /// 前状態と入力から識別子を組む。同じ組から2件の遷移は出ない。
    pub fn 前状態と入力から生成する(前状態: 設計概念への参照, 入力: 設計概念への参照) -> Self {
        Self { 前状態, 入力 }
    }

    /// 遷移する前の状態。
    pub fn 前状態(&self) -> &設計概念への参照 {
        &self.前状態
    }

    /// その状態へ与えた入力。
    pub fn 入力(&self) -> &設計概念への参照 {
        &self.入力
    }

    /// この遷移から組む節点の所有者。前状態と入力の全成分を別々の要素へ保存する。
    pub fn 所有者の並びへ写す(&self) -> Vec<String> {
        vec![self.前状態.同一性を符号化する(), self.入力.同一性を符号化する()]
    }

    /// 命題の項が設計概念への参照だけを取るため、遷移を項へ入れる境界でこの参照へ写す。
    /// 実行時のドメイン概念の名前空間で組むのは、遷移モデルの名前がRustのソースから抽出した項目とは別の名前の空間に在るためである。
    pub fn 設計概念への参照として表す(&self) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(遷移の名前の空間, "遷移").所有者を添える(self.所有者の並びへ写す())
    }

    /// 人が読む1行の表記。**これは表示だけのものであり、同一性の判断に使ってはならない。**
    /// 2つの表記を繋いだ文字列は元の組へ一意には戻らず、別の組が同じ1行になりうる。
    pub fn 表記(&self) -> String {
        format!("{}へ{}を与えた遷移", self.前状態.表記(), self.入力.表記())
    }
}

#[cfg(test)]
mod 遷移の識別子の試験 {
    use super::遷移の識別子;
    use crate::設計概念への参照;

    // 試験の題材の名前の空間。区切りの語と同じ並びを名前の中へ意図して入れるため、空間の表記も名前へ現れる。
    const 題材の名前の空間: &str = "遷移の識別子の試験";

    fn 概念(名前: &str) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(題材の名前の空間, 名前)
    }

    /// 表記を1本へ繋いだ文字列が同じになる2つの組を作り、識別子と、項へ入れる参照が別であることを見る。
    /// 繋いだ文字列だけを識別子にすると、この2件が命題の層で同じ遷移として引き当てられる。
    #[test]
    fn 繋いだ表記が同じになる2つの組でも識別子と参照は別である() {
        let 甲 = 遷移の識別子::前状態と入力から生成する(概念("甲"), 概念(&format!("乙へ{題材の名前の空間}::丙")));
        let 乙 = 遷移の識別子::前状態と入力から生成する(概念(&format!("甲へ{題材の名前の空間}::乙")), 概念("丙"));
        assert_eq!(甲.表記(), 乙.表記(), "この試験は、繋いだ表記が同じになる2つの組を題材にする");
        assert_ne!(甲, 乙, "前状態と入力の組が違うのに識別子が同じになっている");
        assert_ne!(甲.設計概念への参照として表す(), 乙.設計概念への参照として表す(), "別の組の遷移が項の層で同じ参照へ写っている");
    }
}
