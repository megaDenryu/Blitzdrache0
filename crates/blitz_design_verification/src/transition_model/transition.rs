//! 遷移とは、前状態と入力と適用した規則から後状態と出来事が定まった1回の移りのことである。
//!
//! 失敗した遷移は次の状態を採用せず、出来事を1件も生成しない(設計オントロジーの遷移失敗結果の法則)。
//! この法則を後から検査するのではなく、成功と失敗で別の生成の口を置き、失敗の口には出来事を渡す引数を置かないことで守る。
//! フィールドを私有にするのは、構造体リテラルで生成の口を迂回できないようにするためである。
//!
//! 前状態と入力を識別子の中だけに持ち、材料の側へ並べて持たないのは、同じ2つを2箇所へ置くと、
//! 識別子の指す組と材料の並べる組が食い違う状態が型の上で表現可能になるためである。
//! 参照: `_doc/設計/設計オントロジー.md` 3.5.9。

use super::transition_identifier::遷移の識別子;
use crate::設計概念への参照;

/// 遷移1件の材料。識別子が前状態と入力の2つを持ち、ここが足すのは規則だけである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 遷移の材料 {
    /// 遷移モデルの中でこの1件を名指す識別子。前状態と入力の2つをこの識別子が持つ。
    pub 識別子: 遷移の識別子,
    /// その遷移が下で起きた規則。
    pub 適用した規則: 設計概念への参照,
}

/// 遷移モデルの1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 遷移 {
    材料: 遷移の材料,
    後状態: 設計概念への参照,
    生成した出来事一覧: Vec<設計概念への参照>,
    失敗: Option<設計概念への参照>,
}

impl 遷移 {
    /// 成功した遷移を組む。後状態を採用し、その遷移で実際に成立した出来事を持つ。
    pub fn 成功として生成する(材料: 遷移の材料, 後状態: 設計概念への参照, 生成した出来事一覧: Vec<設計概念への参照>) -> Self {
        Self {
            材料, 後状態, 生成した出来事一覧, 失敗: None
        }
    }

    /// 失敗した遷移を組む。次の状態は採用されないため後状態は前状態と同じであり、出来事は1件も生成しない。
    pub fn 失敗として生成する(材料: 遷移の材料, 失敗: 設計概念への参照) -> Self {
        let 後状態 = 材料.識別子.前状態().clone();
        Self {
            材料,
            後状態,
            生成した出来事一覧: Vec::new(),
            失敗: Some(失敗),
        }
    }

    /// この遷移を名指す識別子。
    pub fn 識別子(&self) -> &遷移の識別子 {
        &self.材料.識別子
    }

    /// 遷移する前の状態。
    pub fn 前状態(&self) -> &設計概念への参照 {
        self.材料.識別子.前状態()
    }

    /// その状態へ与えた入力。
    pub fn 入力(&self) -> &設計概念への参照 {
        self.材料.識別子.入力()
    }

    /// その遷移が下で起きた規則。
    pub fn 適用した規則(&self) -> &設計概念への参照 {
        &self.材料.適用した規則
    }

    /// 遷移した後の状態。失敗した遷移では前状態と同じである。
    pub fn 後状態(&self) -> &設計概念への参照 {
        &self.後状態
    }

    /// その遷移で成立した出来事の並び。失敗した遷移では空である。
    pub fn 生成した出来事一覧(&self) -> &[設計概念への参照] {
        &self.生成した出来事一覧
    }

    /// 失敗した遷移ならその失敗。成功した遷移なら値なしである。
    pub fn 失敗(&self) -> Option<&設計概念への参照> {
        self.失敗.as_ref()
    }

    /// その出来事をこの遷移が生成したか。振る舞いの原子命題`発生する`がこの問いに落ちる。
    pub fn その出来事を生成したか(&self, 出来事: &設計概念への参照) -> bool {
        self.生成した出来事一覧.iter().any(|生成した| 生成した == 出来事)
    }
}
