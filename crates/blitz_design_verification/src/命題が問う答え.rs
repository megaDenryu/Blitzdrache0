//! 命題が問う答えとは、命題の真偽がグラフのどの答え(設計関係の結び付き方ごとの在り方・プリミティブな関係の種類ごとの在り方・分類)の不在に依りうるかのことである。
//! 受け取るのは原子命題・対象集合・命題・命題の集合、返すのは欠落が弱める答えの並びである。
//!
//! この答えの並びは2か所が読む。1つは構造の検証器であり、原子の答えをどの欠落が弱めるかと、対象集合の列挙をどの欠落が全件でなくすかを決める。
//! もう1つは設計の検証の合否であり、命題の集合が問う答えを弱める欠落が在るときだけ不合格にする。同じ対応を2か所で書くと、原子を足したときに片方だけ直して
//! 食い違い、検証器が弱める答えと合否が数える答えがずれるため、対応をここに1つだけ置く。
//! 参照: `_doc/設計/設計オントロジー.md` 第9節。

use super::proposition::命題;
use super::quantification::対象集合;
use super::specification::命題の集合;
use super::原子命題の定義::原子命題;
use super::欠落が弱める答えの定義::欠落が弱める答え;

impl 原子命題 {
    /// この原子命題の答えが、辺か分類の不在を根拠にするときに依る答えの並び。振る舞いの原子命題はグラフに依らず、空である。
    /// `設計関係へ1つも参加していない` は全ての種類の設計関係に依り、参加に数えないプリミティブな関係と分類には依らない。
    pub fn 問う答え一覧(&self) -> Vec<欠落が弱める答え> {
        match self {
            Self::設計関係が在る { 種類, .. } | Self::設計関係の経路が在る { 種類, .. } => vec![欠落が弱める答え::設計関係(*種類)],
            Self::プリミティブな関係が在る { 種類, .. } | Self::プリミティブな関係の経路が在る { 種類, .. } => vec![欠落が弱める答え::プリミティブな関係(*種類)],
            Self::マーカーを持つ { .. } => vec![欠落が弱める答え::分類],
            Self::設計関係へ1つも参加していない { .. } => 欠落が弱める答え::全ての設計関係().to_vec(),
            Self::発生する { .. } | Self::遷移する { .. } | Self::到達可能である { .. } => Vec::new(),
        }
    }
}

impl 対象集合 {
    /// グラフから列挙したこの対象集合が全件であることが依る答えの並び。全ての節点の並びは、どの事実を落としても節点を欠きうるため全ての答えに依る。
    /// 遷移モデルが持つ範囲はグラフに依らず、空である。
    pub fn 列挙が依る答え一覧(&self) -> Vec<欠落が弱める答え> {
        match self {
            Self::全ての設計概念 | Self::種類で絞った設計概念(_) => 欠落が弱める答え::全部(),
            Self::マーカーを持つ設計概念 { .. } => vec![欠落が弱める答え::分類],
            Self::全ての設計関係の主語(種類) => vec![欠落が弱める答え::設計関係(*種類)],
            Self::到達可能な状態 | Self::到達可能な遷移 => Vec::new(),
        }
    }
}

impl 命題 {
    /// この命題の答えが依る答えの並び。原子の答えと、量化の対象集合の列挙が依る答えを、重ねずに並べる。
    pub fn 問う答え一覧(&self) -> Vec<欠落が弱める答え> {
        let 並び: Vec<欠落が弱める答え> = match self {
            Self::原子(原子) => 原子.問う答え一覧(),
            Self::否定(本体) => 本体.問う答え一覧(),
            Self::連言(項一覧) | Self::選言(項一覧) => 項一覧.一覧().iter().flat_map(Self::問う答え一覧).collect(),
            Self::含意 { 前件, 後件 } => 前件.問う答え一覧().into_iter().chain(後件.問う答え一覧()).collect(),
            Self::全称 { 対象集合, 本体, .. } | Self::存在 { 対象集合, 本体, .. } => 対象集合.列挙が依る答え一覧().into_iter().chain(本体.問う答え一覧()).collect(),
        };
        重ねずに並べる(並び)
    }
}

impl 命題の集合 {
    /// 集合の全ての命題の答えが依る答えの並び。設計の検証の合否が、この並びを弱める欠落だけを不合格に数える。
    pub fn 問う答え一覧(&self) -> Vec<欠落が弱める答え> {
        重ねずに並べる(self.命題一覧().iter().flat_map(|名前付き| 名前付き.命題().問う答え一覧()).collect())
    }
}

// 先に現れた順を保ち、同じ答えを1つにまとめる。
fn 重ねずに並べる(並び: Vec<欠落が弱める答え>) -> Vec<欠落が弱める答え> {
    let mut 一覧 = Vec::new();
    for 答え in 並び {
        if !一覧.contains(&答え) {
            一覧.push(答え);
        }
    }
    一覧
}
