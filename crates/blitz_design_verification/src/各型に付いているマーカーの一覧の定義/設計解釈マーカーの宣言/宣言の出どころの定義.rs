//! 宣言の出どころとは、抽出器が読み取った宣言1件が、どのソースのどの行から出たかのことである。
//! 設計解釈マーカーの宣言・プリミティブな宣言・導出の根拠が共通に持ち、誤った検証の結果から人がその行へ戻れるようにする。

use std::path::{Path, PathBuf};

/// 宣言1件が、どのソースのどの行から出たか。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 宣言の出どころ {
    パス: PathBuf, // リポジトリからの相対のソースのパス
    行番号: usize, // そのソースの中の行番号。1始まりである
}

impl 宣言の出どころ {
    /// リポジトリからの相対のソースのパスと、そのソースの中の1始まりの行番号から組む。
    pub fn 生成する(パス: PathBuf, 行番号: usize) -> Self {
        Self { パス, 行番号 }
    }

    /// リポジトリからの相対のソースのパスを読む。
    pub fn パス(&self) -> &Path {
        &self.パス
    }

    /// そのソースの中の1始まりの行番号を読む。
    pub fn 行番号(&self) -> usize {
        self.行番号
    }
}
