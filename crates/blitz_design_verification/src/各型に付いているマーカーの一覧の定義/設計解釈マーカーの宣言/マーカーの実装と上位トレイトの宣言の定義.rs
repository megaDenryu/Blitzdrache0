//! マーカーの実装(`impl マーカー for 型`)と上位トレイトの宣言(`trait A: B`)の1件ずつの型。
//! 2つを同じファイルに置くのは、どちらも2つの設計概念の識別用情報と宣言の出どころを持つ、設計解釈マーカーについての宣言の1件であり、
//! 設計解釈マーカーの宣言の一覧が同じ形で端点を確かめるためである。

use super::宣言の出どころ;
use crate::設計概念の識別用情報;

/// `impl マーカー for 型` の1件。型がそのマーカーを直に実装している宣言である。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct マーカーの実装 {
    型: 設計概念の識別用情報,       // マーカーを実装した型への参照
    マーカー: 設計概念の識別用情報, // 実装された設計解釈マーカーのトレイトへの参照
    出どころ: 宣言の出どころ,
}

/// `trait トレイト: 上位トレイト` の、上位トレイト1つぶんの1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 上位トレイトの宣言 {
    トレイト: 設計概念の識別用情報,     // 上位トレイトを宣言したトレイトへの参照
    上位トレイト: 設計概念の識別用情報, // 宣言された上位トレイトへの参照
    出どころ: 宣言の出どころ,
}

impl マーカーの実装 {
    /// マーカーを実装した型と、実装された設計解釈マーカーと、宣言の出どころから組む。
    pub fn 生成する(型: 設計概念の識別用情報, マーカー: 設計概念の識別用情報, 出どころ: 宣言の出どころ) -> Self {
        Self { 型, マーカー, 出どころ }
    }

    /// マーカーを実装した型への参照を読む。
    pub fn 型(&self) -> &設計概念の識別用情報 {
        &self.型
    }

    /// 実装された設計解釈マーカーのトレイトへの参照を読む。
    pub fn マーカー(&self) -> &設計概念の識別用情報 {
        &self.マーカー
    }

    /// この1件がどのソースのどの行から出たかを読む。
    pub fn 出どころ(&self) -> &宣言の出どころ {
        &self.出どころ
    }

    /// 人が読む1行の表記。`旅行者 は M状態 を実装する` の形である。
    pub fn 表記(&self) -> String {
        format!("{} は {} を実装する", self.型.表記(), self.マーカー.表記())
    }
}

impl 上位トレイトの宣言 {
    /// 上位トレイトを宣言したトレイトと、宣言された上位トレイトと、宣言の出どころから組む。
    pub fn 生成する(トレイト: 設計概念の識別用情報, 上位トレイト: 設計概念の識別用情報, 出どころ: 宣言の出どころ) -> Self {
        Self {
            トレイト, 上位トレイト, 出どころ
        }
    }

    /// 上位トレイトを宣言したトレイトへの参照を読む。
    pub fn トレイト(&self) -> &設計概念の識別用情報 {
        &self.トレイト
    }

    /// 宣言された上位トレイトへの参照を読む。
    pub fn 上位トレイト(&self) -> &設計概念の識別用情報 {
        &self.上位トレイト
    }

    /// この1件がどのソースのどの行から出たかを読む。
    pub fn 出どころ(&self) -> &宣言の出どころ {
        &self.出どころ
    }

    /// 人が読む1行の表記。`M状態 は M不変データ を上位トレイトに持つ` の形である。
    pub fn 表記(&self) -> String {
        format!("{} は {} を上位トレイトに持つ", self.トレイト.表記(), self.上位トレイト.表記())
    }
}
