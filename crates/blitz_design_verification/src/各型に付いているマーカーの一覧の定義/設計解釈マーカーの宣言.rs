//! 設計解釈マーカーの宣言の一覧とは、コードから読み取った、設計解釈マーカーについての宣言の一覧のことである。
//! 付いているマーカーに含まれうるトレイトである設計解釈マーカーの一覧と、マーカーの実装(`impl マーカー for 型`)の一覧と、上位トレイトの宣言(`trait A: B`)の一覧の3つを、抽出したまま並べて持つ。
//!
//! **付いているマーカーは設計関係ではない。** `impl M状態 for 旅行者` は、型へ「設計上これである」という付いているマーカーを与える宣言であり、2つの概念のあいだの関係ではない。
//! `trait M状態: M不変データ` は設計解釈マーカーどうしの一種であるという関係であり、オントロジーの公理に属する。どちらも設計関係グラフのエッジにせず、
//! グラフが `各型に付いているマーカーの一覧` としてノードのラベルへ閉じて持つ。
//! 公理の正本は `blitz_design` の上位トレイトの宣言である。コンパイラが既に強制しているため、手書きの公理の表を別に作らない。
//!
//! **設計解釈マーカーの一覧は、抽出器が渡す。** 検証器はどのトレイトが設計解釈マーカーかを自分で持たない。マーカーの正本の一覧は
//! `cargo xtask conform` が `blitz_design` の宣言と突き合わせて持つものであり、検証器の側へ写しを置くと2か所で食い違いうるためである。
//! 上位トレイトの宣言は、`Clone` のような標準のトレイトを上位に持つ宣言も抽出したまま持つ。付いているマーカーへ入れるかは閉包の側が決める。
//! 参照: Issue #193「分類と公理」、`_doc/設計/設計オントロジー.md` 第6節。

#[path = "設計解釈マーカーの宣言/マーカーの実装と上位トレイトの宣言の定義.rs"]
mod マーカーの実装と上位トレイトの宣言の定義;
#[path = "設計解釈マーカーの宣言/宣言の出どころの定義.rs"]
mod 宣言の出どころの定義;

use crate::設計概念の識別用情報;

pub use マーカーの実装と上位トレイトの宣言の定義::{マーカーの実装, 上位トレイトの宣言};
pub use 宣言の出どころの定義::宣言の出どころ;

/// コードから読み取った、設計解釈マーカーについての宣言の一覧。設計解釈マーカーの一覧と、マーカーの実装の一覧と、上位トレイトの宣言の一覧の3つを持つ。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct 設計解釈マーカーの宣言の一覧 {
    設計解釈マーカー一覧: Vec<設計概念の識別用情報>, // 付いているマーカーに含まれうるトレイト
    マーカーの実装一覧: Vec<マーカーの実装>,
    上位トレイトの宣言一覧: Vec<上位トレイトの宣言>,
}

impl 設計解釈マーカーの宣言の一覧 {
    /// 設計解釈マーカーの一覧と、マーカーの実装の一覧と、上位トレイトの宣言の一覧から組む。
    pub fn 生成する(設計解釈マーカー一覧: Vec<設計概念の識別用情報>, マーカーの実装一覧: Vec<マーカーの実装>, 上位トレイトの宣言一覧: Vec<上位トレイトの宣言>) -> Self {
        Self {
            設計解釈マーカー一覧,
            マーカーの実装一覧,
            上位トレイトの宣言一覧,
        }
    }

    /// 宣言を1件も持たないもの。付いているマーカーを問わない試験がこれを渡す。
    pub fn 無い() -> Self {
        Self::default()
    }

    /// 付いているマーカーに含まれうるトレイトである、全ての設計解釈マーカー。
    pub fn 設計解釈マーカー一覧(&self) -> &[設計概念の識別用情報] {
        &self.設計解釈マーカー一覧
    }

    /// 全てのマーカーの実装。
    pub fn マーカーの実装一覧(&self) -> &[マーカーの実装] {
        &self.マーカーの実装一覧
    }

    /// 全ての上位トレイトの宣言。
    pub fn 上位トレイトの宣言一覧(&self) -> &[上位トレイトの宣言] {
        &self.上位トレイトの宣言一覧
    }

    /// 端点のどれかがノードを持たない宣言を除いた宣言と、除いた宣言の端点のうちノードを持たないものの並びを返す。
    /// 設計関係のエッジと同じく、ノードの無い端点を黙って落とさずに返し、グラフの組み立てがそれを欠落として数えられるようにする。
    pub(crate) fn 端点にノードが在るものだけを残す(self, ノードが在るか: impl Fn(&設計概念の識別用情報) -> bool) -> (Self, Vec<設計概念の識別用情報>) {
        let mut ノードが無い端点一覧 = Vec::new();
        let mut 端点を確かめる = |端点一覧: [&設計概念の識別用情報; 2]| {
            let 無い端点: Vec<設計概念の識別用情報> = 端点一覧.into_iter().filter(|端点| !ノードが在るか(端点)).cloned().collect();
            let 揃っているか = 無い端点.is_empty();
            ノードが無い端点一覧.extend(無い端点);
            揃っているか
        };
        let マーカーの実装一覧 = self.マーカーの実装一覧.into_iter().filter(|マーカーの実装| 端点を確かめる([マーカーの実装.型(), マーカーの実装.マーカー()])).collect();
        let 上位トレイトの宣言一覧 = self
            .上位トレイトの宣言一覧
            .into_iter()
            .filter(|上位トレイトの宣言| 端点を確かめる([上位トレイトの宣言.トレイト(), 上位トレイトの宣言.上位トレイト()]))
            .collect();
        (
            Self {
                設計解釈マーカー一覧: self.設計解釈マーカー一覧,
                マーカーの実装一覧,
                上位トレイトの宣言一覧,
            },
            ノードが無い端点一覧,
        )
    }
}
