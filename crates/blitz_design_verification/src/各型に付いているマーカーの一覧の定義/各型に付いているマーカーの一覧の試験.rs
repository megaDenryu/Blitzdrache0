//! 各型に付いているマーカーの一覧が、マーカーの実装を上位トレイトの宣言で閉じることと、閉包が設計解釈マーカーだけを辿って標準のトレイトを付いているマーカーへ入れないことと、
//! 端点のノードが無い宣言を黙って捨てないことを固定する試験。

use std::path::PathBuf;

use crate::{マーカーの実装, 上位トレイトの宣言, 宣言の出どころ, 設計概念への参照, 設計概念ノード, 設計解釈マーカーの宣言の一覧, 設計関係グラフ};

const 正本: &str = "blitz_design::marker";

fn トレイト(名前: &str) -> 設計概念への参照 {
    設計概念への参照::トレイトとして生成する(正本, 名前)
}

fn 型(名前: &str) -> 設計概念への参照 {
    設計概念への参照::型として生成する("blitz_esca::traveler", 名前)
}

fn 出どころ() -> 宣言の出どころ {
    宣言の出どころ {
        パス: PathBuf::from("crates/blitz_design/src/付いているマーカーの試験の出どころ.rs"),
        行番号: 1,
    }
}

fn 上位(下: &str, 上: &str) -> 上位トレイトの宣言 {
    上位トレイトの宣言 {
        トレイト: トレイト(下),
        上位トレイト: トレイト(上),
        出どころ: 出どころ(),
    }
}

fn 実装(型の名前: &str, マーカー: &str) -> マーカーの実装 {
    マーカーの実装 {
        型: 型(型の名前),
        マーカー: トレイト(マーカー),
        出どころ: 出どころ(),
    }
}

/// `M時間局所状態: M状態: M不変データ: Clone` の3段の宣言と、`時間局所の型` が `M時間局所状態` だけを実装する宣言を持つグラフ。
/// 設計解釈マーカーは `Clone` を除く3つである。
fn 三段のグラフ(設計解釈マーカーの宣言の一覧: 設計解釈マーカーの宣言の一覧) -> 設計関係グラフ {
    let mut 概念一覧: Vec<設計概念ノード> = ["M時間局所状態", "M状態", "M不変データ", "Clone"].into_iter().map(|名前| 設計概念ノード::トレイトとして生成する(正本, 名前)).collect();
    概念一覧.push(設計概念ノード::型として生成する("blitz_esca::traveler", "時間局所の型"));
    設計関係グラフ::生成する(概念一覧, Vec::new(), Vec::new(), 設計解釈マーカーの宣言の一覧).グラフ
}

fn 三段のマーカー一覧() -> Vec<設計概念への参照> {
    ["M時間局所状態", "M状態", "M不変データ"].map(トレイト).to_vec()
}

fn 三段の設計解釈マーカーの宣言の一覧() -> 設計解釈マーカーの宣言の一覧 {
    設計解釈マーカーの宣言の一覧::生成する(
        三段のマーカー一覧(),
        vec![実装("時間局所の型", "M時間局所状態")],
        vec![上位("M時間局所状態", "M状態"), 上位("M状態", "M不変データ"), 上位("M不変データ", "Clone")],
    )
}

#[test]
fn 付いているマーカーは上位トレイトの宣言を何段でも辿って閉じる() {
    let グラフ = 三段のグラフ(三段の設計解釈マーカーの宣言の一覧());
    assert_eq!(
        グラフ.各型に付いているマーカーの一覧を貸す().概念に付いているマーカー(&型("時間局所の型")),
        &[トレイト("M時間局所状態"), トレイト("M状態"), トレイト("M不変データ")],
        "閉包が設計解釈マーカーの上位トレイトの宣言の連なりを辿り切っていないか、標準のトレイトを付いているマーカーへ入れている"
    );
}

#[test]
fn 標準のトレイトは上位トレイトの宣言に在っても付いているマーカーに含まれない() {
    let グラフ = 三段のグラフ(三段の設計解釈マーカーの宣言の一覧());
    assert!(
        !グラフ.各型に付いているマーカーの一覧を貸す().付いているマーカーがトレイトを含むか(&型("時間局所の型"), &トレイト("Clone")),
        "設計解釈マーカーでない Clone を付いているマーカーへ入れている"
    );
    assert!(グラフ.各型に付いているマーカーの一覧を貸す().名前のトレイトが付いている概念一覧("Clone").is_empty());
    assert!(グラフ.各型に付いているマーカーの一覧を貸す().名前の設計解釈マーカー一覧("Clone").is_empty());
    assert!(グラフ.各型に付いているマーカーの一覧を貸す().宣言に現れるか(&トレイト("Clone")), "上位トレイトの宣言そのものは抽出したまま持つ");
}

#[test]
fn 設計解釈マーカーでないトレイトを実装した宣言は付いているマーカーに含まれない() {
    let 設計解釈マーカーの宣言の一覧 = 設計解釈マーカーの宣言の一覧::生成する(三段のマーカー一覧(), vec![実装("時間局所の型", "Clone")], Vec::new());
    assert!(三段のグラフ(設計解釈マーカーの宣言の一覧).各型に付いているマーカーの一覧を貸す().概念に付いているマーカー(&型("時間局所の型")).is_empty());
}

#[test]
fn トレイトは上位トレイトの宣言があってもマーカーが付かない() {
    let グラフ = 三段のグラフ(三段の設計解釈マーカーの宣言の一覧());
    assert!(グラフ.各型に付いているマーカーの一覧を貸す().概念に付いているマーカー(&トレイト("M状態")).is_empty());
    assert!(グラフ.各型に付いているマーカーの一覧を貸す().名前のトレイトが付いている概念一覧("M不変データ").iter().all(|概念| **概念 == 型("時間局所の型")));
    assert!(グラフ.各型に付いているマーカーの一覧を貸す().宣言に現れるか(&トレイト("M状態")), "公理に現れるトレイトを宣言に現れないと答えている");
}

#[test]
fn 付いているマーカーは設計関係のエッジにならない() {
    let グラフ = 三段のグラフ(三段の設計解釈マーカーの宣言の一覧());
    assert!(グラフ.関係一覧().is_empty());
    assert!(グラフ.設計関係へ1つも参加していないか(&型("時間局所の型")));
}

#[test]
fn 端点のノードが無い設計解釈マーカーの宣言の一覧は捨てずノードが無い端点として残す() {
    let マーカー一覧 = ["M未登録", "M時間局所状態", "M状態", "M不変データ"].map(トレイト).to_vec();
    let 設計解釈マーカーの宣言の一覧 = 設計解釈マーカーの宣言の一覧::生成する(マーカー一覧, vec![実装("時間局所の型", "M未登録")], vec![上位("M未登録", "M状態")]);
    let グラフ = 三段のグラフ(設計解釈マーカーの宣言の一覧);
    assert_eq!(グラフ.ノードが無い端点一覧(), &[トレイト("M未登録")]);
    assert!(グラフ.各型に付いているマーカーの一覧を貸す().概念に付いているマーカー(&型("時間局所の型")).is_empty());
}
