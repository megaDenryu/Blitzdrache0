//! 落とした理由ごとの件数とは、設計関係を抽出し漏らした理由1件ぶんの、人が読む説明と、その件数と、その件が不在を根拠にできなくする答えの並びの組のことである。
//! 設計関係の抽出漏れがこの値を並べて持ち、答えを弱めるかの問いと人が読む説明の両方がこの値を読む。

use crate::欠落が弱める答え;

/// 設計関係を抽出し漏らした理由1件ぶんの、人が読む説明とその件数。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 落とした理由ごとの件数 {
    理由の説明: String,                    // 人が読む理由の説明。未決定の理由の文がこれを並べる
    件数: usize,                           // その理由で設計関係を抽出し漏らした件数
    弱める答え一覧: Vec<欠落が弱める答え>, // その理由の件が不在を根拠にできなくする答えの並び
}

impl 落とした理由ごとの件数 {
    /// 人が読む理由の説明と、その理由で設計関係を抽出し漏らした件数と、その件が弱める答えの並びから組む。
    pub fn 生成する(理由の説明: String, 件数: usize, 弱める答え一覧: Vec<欠落が弱める答え>) -> Self {
        Self {
            理由の説明, 件数, 弱める答え一覧
        }
    }

    /// 人が読む理由の説明を読む。
    pub fn 理由の説明(&self) -> &str {
        &self.理由の説明
    }

    /// その理由で設計関係を抽出し漏らした件数を読む。
    pub fn 件数(&self) -> usize {
        self.件数
    }

    /// その理由の件が不在を根拠にできなくする答えの並びを読む。
    pub fn 弱める答え一覧(&self) -> &[欠落が弱める答え] {
        &self.弱める答え一覧
    }

    /// 並べた答えのどれかを弱めるか。
    pub(super) fn どれかの答えを弱めるか(&self, 答え一覧: &[欠落が弱める答え]) -> bool {
        self.弱める答え一覧.iter().any(|答え| 答え一覧.contains(答え))
    }

    /// 人が読む1項目。同じ呼び名の件が弱める答えの違いで2つ並びうるため、弱める答えの語を添えて見分けられるようにする。
    pub(super) fn 表記(&self) -> String {
        let 語一覧: Vec<&str> = self.弱める答え一覧.iter().map(|答え| 答え.語()).collect();
        format!("{}: {}件(弱める答え: {})", self.理由の説明, self.件数, 語一覧.join("・"))
    }
}
