//! 設計関係グラフへの問いが、端点が名乗る種類を答えへ効かせることを固定する試験。
//!
//! 見ているのは偽陽性の封じである。`トレイト Foo` から1本だけ張ったエッジを `型 Foo` についての問いが借りて答えると、
//! 実装に無い関係が証明済みになる。したがってエッジもノードも、識別子だけでなく種類まで一致する問いにだけ見えなければならない。
//! 種類を照合へ入れた結果として抽出器の推測が外れたエッジが問いから消えることは、同一性の衝突と `関係を落とした抽出の欠落` が受け止める。

use crate::{プリミティブな関係の種類, 経路の答え, 設計概念ノード, 設計解釈マーカーの宣言の一覧, 設計関係グラフ, 関数の引数と戻り値の役目};

use super::{エッジ, トレイトの参照, 保持するエッジ, 名前の空間, 型の参照};

#[test]
fn 割れたノードへ張ったエッジは種類の違う参照の問いからは見えない() {
    let 結果 = 設計関係グラフ::生成する(
        vec![
            設計概念ノード::型として生成する(名前の空間, "旅行者"),
            設計概念ノード::型として生成する(名前の空間, "現在地"),
            設計概念ノード::トレイトとして生成する(名前の空間, "現在地"),
            設計概念ノード::型として生成する(名前の空間, "東西の位置"),
        ],
        Vec::new(),
        vec![保持するエッジ("旅行者", "現在地"), 保持するエッジ("現在地", "東西の位置")],
        設計解釈マーカーの宣言の一覧::無い(),
    );
    assert_eq!(結果.同一性の衝突一覧.len(), 1, "この試験の前提である衝突が1件で起きていない");
    let グラフ = &結果.グラフ;
    assert!(
        グラフ.プリミティブな関係を貸す().在るか(&型の参照("旅行者"), プリミティブな関係の種類::保持する, &型の参照("現在地")),
        "種類の合う問いからエッジが見えていない"
    );
    assert!(
        !グラフ.プリミティブな関係を貸す().在るか(&型の参照("旅行者"), プリミティブな関係の種類::保持する, &トレイトの参照("現在地")),
        "型のノードへ張ったエッジをトレイトの参照の問いが借りている"
    );
    assert!(
        !グラフ.プリミティブな関係を貸す().在るか(&トレイトの参照("現在地"), プリミティブな関係の種類::保持する, &型の参照("東西の位置")),
        "型のノードから出るエッジをトレイトの参照の問いが借りている"
    );
    assert_eq!(
        グラフ.プリミティブな関係の経路が在るか(&型の参照("旅行者"), プリミティブな関係の種類::保持する, &トレイトの参照("現在地")),
        経路の答え::達しない,
        "種類の違う目的語へ経路が繋がったと答えている"
    );
}

#[test]
fn トレイトから張ったエッジを同じ名前の型の問いが借りない() {
    // レビューが挙げた偽陽性の形をそのまま題材にする。トレイトFooだけがトレイトMへのエッジを持ち、型Fooは1本もエッジを持たない。
    let 結び付き方 = 関数の引数と戻り値の役目::参照する.設計関係の結び付き方へ写す();
    let 結果 = 設計関係グラフ::生成する(
        vec![
            設計概念ノード::型として生成する(名前の空間, "Foo"),
            設計概念ノード::トレイトとして生成する(名前の空間, "Foo"),
            設計概念ノード::トレイトとして生成する(名前の空間, "M"),
        ],
        vec![エッジ(トレイトの参照("Foo"), 結び付き方, トレイトの参照("M"))],
        Vec::new(),
        設計解釈マーカーの宣言の一覧::無い(),
    );
    let グラフ = &結果.グラフ;
    assert!(グラフ.関係が在るか(&トレイトの参照("Foo"), 結び付き方, &トレイトの参照("M")), "トレイトFooのエッジがトレイトFooの問いから見えていない");
    assert!(!グラフ.関係が在るか(&型の参照("Foo"), 結び付き方, &トレイトの参照("M")), "トレイトFooのエッジを型Fooの問いが借りている");
    assert_eq!(グラフ.経路が在るか(&型の参照("Foo"), &[結び付き方], &トレイトの参照("M")), 経路の答え::達しない, "トレイトFooのエッジを型Fooの経路の問いが借りている");
    assert!(グラフ.設計関係へ1つも参加していないか(&型の参照("Foo")), "1本もエッジを持たない型Fooが、同じ名前のトレイトのエッジで参加していると答えられている");
}

#[test]
fn 種類の合うノードだけが実在すると答えられる() {
    let 結果 = 設計関係グラフ::生成する(vec![設計概念ノード::トレイトとして生成する(名前の空間, "Foo")], Vec::new(), Vec::new(), 設計解釈マーカーの宣言の一覧::無い());
    let グラフ = &結果.グラフ;
    assert!(グラフ.ノードを貸す().在るか(&トレイトの参照("Foo")), "在るトレイトのノードを無いと答えている");
    assert!(!グラフ.ノードを貸す().在るか(&型の参照("Foo")), "同じ名前のトレイトしか無いのに型のノードが在ると答えている");
}
