//! 節点の分類が、マーカーの実装の事実を上位トレイトの宣言の事実で閉じることと、閉包が設計解釈マーカーだけを辿って標準のトレイトを分類へ入れないことと、
//! 端点の節点が無い事実を黙って捨てないことを固定する試験。

use std::path::PathBuf;

use crate::{マーカーの実装の事実, 上位トレイトの宣言の事実, 事実の出どころ, 分類の事実, 設計概念, 設計概念への参照, 設計関係グラフ};

const 正本: &str = "blitz_design::marker";

fn トレイト(名前: &str) -> 設計概念への参照 {
    設計概念への参照::トレイトとして生成する(正本, 名前)
}

fn 型(名前: &str) -> 設計概念への参照 {
    設計概念への参照::型として生成する("blitz_esca::traveler", 名前)
}

fn 出どころ() -> 事実の出どころ {
    事実の出どころ {
        パス: PathBuf::from("crates/blitz_design/src/分類の試験の出どころ.rs"),
        行番号: 1,
    }
}

fn 上位(下: &str, 上: &str) -> 上位トレイトの宣言の事実 {
    上位トレイトの宣言の事実 {
        トレイト: トレイト(下),
        上位トレイト: トレイト(上),
        出どころ: 出どころ(),
    }
}

fn 実装(型の名前: &str, マーカー: &str) -> マーカーの実装の事実 {
    マーカーの実装の事実 {
        型: 型(型の名前),
        マーカー: トレイト(マーカー),
        出どころ: 出どころ(),
    }
}

/// `M時間局所状態: M状態: M不変データ: Clone` の3段の宣言と、`時間局所の型` が `M時間局所状態` だけを実装する事実を持つグラフ。
/// 設計解釈マーカーは `Clone` を除く3つである。
fn 三段のグラフ(事実: 分類の事実) -> 設計関係グラフ {
    let mut 概念一覧: Vec<設計概念> = ["M時間局所状態", "M状態", "M不変データ", "Clone"].into_iter().map(|名前| 設計概念::トレイトとして生成する(正本, 名前)).collect();
    概念一覧.push(設計概念::型として生成する("blitz_esca::traveler", "時間局所の型"));
    設計関係グラフ::生成する(概念一覧, Vec::new(), 事実).グラフ
}

fn 三段のマーカー一覧() -> Vec<設計概念への参照> {
    ["M時間局所状態", "M状態", "M不変データ"].map(トレイト).to_vec()
}

fn 三段の事実() -> 分類の事実 {
    分類の事実::生成する(
        三段のマーカー一覧(),
        vec![実装("時間局所の型", "M時間局所状態")],
        vec![上位("M時間局所状態", "M状態"), 上位("M状態", "M不変データ"), 上位("M不変データ", "Clone")],
    )
}

#[test]
fn 分類は上位トレイトの宣言を何段でも辿って閉じる() {
    let グラフ = 三段のグラフ(三段の事実());
    assert_eq!(
        グラフ.分類を貸す().概念の分類(&型("時間局所の型")),
        &[トレイト("M時間局所状態"), トレイト("M状態"), トレイト("M不変データ")],
        "閉包が設計解釈マーカーの上位トレイトの宣言の連なりを辿り切っていないか、標準のトレイトを分類へ入れている"
    );
}

#[test]
fn 標準のトレイトは上位トレイトの宣言に在っても分類に入らない() {
    let グラフ = 三段のグラフ(三段の事実());
    assert!(!グラフ.分類を貸す().分類がトレイトを含むか(&型("時間局所の型"), &トレイト("Clone")), "設計解釈マーカーでない Clone を分類へ入れている");
    assert!(グラフ.分類を貸す().名前のトレイトを分類に持つ概念一覧("Clone").is_empty());
    assert!(グラフ.分類を貸す().名前の設計解釈マーカー一覧("Clone").is_empty());
    assert!(グラフ.分類を貸す().事実に現れるか(&トレイト("Clone")), "上位トレイトの宣言の事実そのものは抽出したまま持つ");
}

#[test]
fn 設計解釈マーカーでないトレイトを実装した事実は分類に入らない() {
    let 事実 = 分類の事実::生成する(三段のマーカー一覧(), vec![実装("時間局所の型", "Clone")], Vec::new());
    assert!(三段のグラフ(事実).分類を貸す().概念の分類(&型("時間局所の型")).is_empty());
}

#[test]
fn トレイトは上位トレイトの宣言があっても分類を持たない() {
    let グラフ = 三段のグラフ(三段の事実());
    assert!(グラフ.分類を貸す().概念の分類(&トレイト("M状態")).is_empty());
    assert!(グラフ.分類を貸す().名前のトレイトを分類に持つ概念一覧("M不変データ").iter().all(|概念| **概念 == 型("時間局所の型")));
    assert!(グラフ.分類を貸す().事実に現れるか(&トレイト("M状態")), "公理に現れるトレイトを事実に現れないと答えている");
}

#[test]
fn 分類は設計関係の辺にならない() {
    let グラフ = 三段のグラフ(三段の事実());
    assert!(グラフ.関係一覧().is_empty());
    assert!(グラフ.関係へ1つも参加していないか(&型("時間局所の型")));
}

#[test]
fn 端点の節点が無い分類の事実は捨てず節点が無い端点として残す() {
    let マーカー一覧 = ["M未登録", "M時間局所状態", "M状態", "M不変データ"].map(トレイト).to_vec();
    let 事実 = 分類の事実::生成する(マーカー一覧, vec![実装("時間局所の型", "M未登録")], vec![上位("M未登録", "M状態")]);
    let グラフ = 三段のグラフ(事実);
    assert_eq!(グラフ.節点が無い端点一覧(), &[トレイト("M未登録")]);
    assert!(グラフ.分類を貸す().概念の分類(&型("時間局所の型")).is_empty());
}
