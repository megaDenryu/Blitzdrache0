//! 分類の事実とは、型の分類を決める2種類の事実(マーカーの実装と上位トレイトの宣言)を、抽出したまま並べたもののことである。
//! あわせて、分類に入りうるトレイトである設計解釈マーカーの一覧を持つ。
//!
//! **分類は設計関係ではない。** `impl M状態 for 旅行者` は、型へ「設計上これである」という分類を与える宣言であり、2つの概念のあいだの関係ではない。
//! `trait M状態: M不変データ` は分類どうしの一種であるという関係であり、オントロジーの公理に属する。どちらも設計関係グラフの辺にせず、
//! グラフが `節点の分類` として節点のラベルへ閉じて持つ。
//! 公理の正本は `blitz_design` の上位トレイトの宣言である。コンパイラが既に強制しているため、手書きの公理の表を別に作らない。
//!
//! **設計解釈マーカーの一覧は、抽出器が渡す。** 検証器はどのトレイトが設計解釈マーカーかを自分で持たない。マーカーの正本の一覧は
//! `cargo xtask conform` が `blitz_design` の宣言と突き合わせて持つものであり、検証器の側へ写しを置くと2か所で食い違いうるためである。
//! 上位トレイトの宣言の事実は、`Clone` のような標準のトレイトを上位に持つ宣言も抽出したまま持つ。分類へ入れるかは閉包の側が決める。
//! 参照: Issue #193「分類と公理」、`_doc/設計/設計オントロジー.md` 第6節。

use std::path::PathBuf;

use crate::設計概念への参照;

/// 事実1件が、どのソースのどの行から出たか。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 事実の出どころ {
    /// リポジトリからの相対のソースのパス。
    pub パス: PathBuf,
    /// そのソースの中の行番号。1始まりである。
    pub 行番号: usize,
}

/// `impl マーカー for 型` の1件。型がそのマーカーを直に実装している事実である。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct マーカーの実装の事実 {
    /// マーカーを実装した型への参照。
    pub 型: 設計概念への参照,
    /// 実装された設計解釈マーカーのトレイトへの参照。
    pub マーカー: 設計概念への参照,
    /// この1件がどのソースのどの行から出たか。
    pub 出どころ: 事実の出どころ,
}

/// `trait トレイト: 上位トレイト` の、上位トレイト1つぶんの1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 上位トレイトの宣言の事実 {
    /// 上位トレイトを宣言したトレイトへの参照。
    pub トレイト: 設計概念への参照,
    /// 宣言された上位トレイトへの参照。
    pub 上位トレイト: 設計概念への参照,
    /// この1件がどのソースのどの行から出たか。
    pub 出どころ: 事実の出どころ,
}

/// 分類を決める事実の全体。設計解釈マーカーの一覧と、マーカーの実装の一覧と、上位トレイトの宣言の一覧の3つを持つ。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct 分類の事実 {
    設計解釈マーカー一覧: Vec<設計概念への参照>, // 分類に入りうるトレイト
    マーカーの実装一覧: Vec<マーカーの実装の事実>,
    上位トレイトの宣言一覧: Vec<上位トレイトの宣言の事実>,
}

impl マーカーの実装の事実 {
    /// 人が読む1行の表記。`旅行者 は M状態 を実装する` の形である。
    pub fn 表記(&self) -> String {
        format!("{} は {} を実装する", self.型.表記(), self.マーカー.表記())
    }
}

impl 上位トレイトの宣言の事実 {
    /// 人が読む1行の表記。`M状態 は M不変データ を上位トレイトに持つ` の形である。
    pub fn 表記(&self) -> String {
        format!("{} は {} を上位トレイトに持つ", self.トレイト.表記(), self.上位トレイト.表記())
    }
}

impl 分類の事実 {
    /// 設計解釈マーカーの一覧と、マーカーの実装の一覧と、上位トレイトの宣言の一覧から組む。
    pub fn 生成する(設計解釈マーカー一覧: Vec<設計概念への参照>, マーカーの実装一覧: Vec<マーカーの実装の事実>, 上位トレイトの宣言一覧: Vec<上位トレイトの宣言の事実>) -> Self {
        Self {
            設計解釈マーカー一覧,
            マーカーの実装一覧,
            上位トレイトの宣言一覧,
        }
    }

    /// 事実を1件も持たないもの。分類を問わない試験がこれを渡す。
    pub fn 無い() -> Self {
        Self::default()
    }

    /// 分類に入りうるトレイトである、全ての設計解釈マーカー。
    pub fn 設計解釈マーカー一覧(&self) -> &[設計概念への参照] {
        &self.設計解釈マーカー一覧
    }

    /// 全てのマーカーの実装の事実。
    pub fn マーカーの実装一覧(&self) -> &[マーカーの実装の事実] {
        &self.マーカーの実装一覧
    }

    /// 全ての上位トレイトの宣言の事実。
    pub fn 上位トレイトの宣言一覧(&self) -> &[上位トレイトの宣言の事実] {
        &self.上位トレイトの宣言一覧
    }

    /// 端点のどれかが節点を持たない事実を除いた事実と、除いた事実の端点のうち節点を持たないものの並びを返す。
    /// 設計関係の辺と同じく、節点の無い端点を黙って落とさずに返し、グラフの組み立てがそれを欠落として数えられるようにする。
    pub(crate) fn 端点に節点が在るものだけを残す(self, 節点が在るか: impl Fn(&設計概念への参照) -> bool) -> (Self, Vec<設計概念への参照>) {
        let mut 節点が無い端点一覧 = Vec::new();
        let mut 端点を確かめる = |端点一覧: [&設計概念への参照; 2]| {
            let 無い端点: Vec<設計概念への参照> = 端点一覧.into_iter().filter(|端点| !節点が在るか(端点)).cloned().collect();
            let 揃っているか = 無い端点.is_empty();
            節点が無い端点一覧.extend(無い端点);
            揃っているか
        };
        let マーカーの実装一覧 = self.マーカーの実装一覧.into_iter().filter(|事実| 端点を確かめる([&事実.型, &事実.マーカー])).collect();
        let 上位トレイトの宣言一覧 = self.上位トレイトの宣言一覧.into_iter().filter(|事実| 端点を確かめる([&事実.トレイト, &事実.上位トレイト])).collect();
        (
            Self {
                設計解釈マーカー一覧: self.設計解釈マーカー一覧,
                マーカーの実装一覧,
                上位トレイトの宣言一覧,
            },
            節点が無い端点一覧,
        )
    }
}
