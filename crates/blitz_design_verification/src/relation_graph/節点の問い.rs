//! 節点の一覧とは、設計関係グラフが持つ節点(設計概念)の全件と、辺に触れない節点そのものについての問いを持つ部分の型のことである。
//! 設計関係グラフの側には、節点と辺の両方に触れる問い(問う答えを持つ空の節点・設計関係への参加)だけを置く。
//! 辺についての問いは `設計関係の問い`・`プリミティブな関係の問い`・`経路` が持つ。
//!
//! 設計関係グラフから切り出したのは、節点の実在・種類での絞り込み・定義をたどれたかだけが違う同じ名前の節点の問いが辺に触れず、
//! グラフの型に置くとグラフのメソッドが問いの数だけ増えるためである。グラフはこの型を保持し、借りた問いの口を1つだけ持つ。
//!
//! 定義をたどれずモジュールパスが空の節点は、定義をたどれた同じ名前の節点と別の節点になる。抽出器がある表記や実装の対象から型の定義をたどれなかったとき、
//! その表記から導いた辺やその実装から読んだ分類は空の節点に付き、定義をたどれた節点には付かない。そのため、定義をたどれた節点への問いは
//! 辺か分類の不在を答えてしまう。この取り違えを問いの側で止めるため、同じ名前と種類の空の節点が、その問いが問う答えの種類の辺か分類を持つかを答える問いを置く。
//! 答えの種類で絞るのは、関数の署名が引数と戻り値から多くの空の節点を作るとき、その空の節点が持つ引数に取る・返すの辺のために、
//! 署名と関係の無い設計関係・保持する・分類の問いまで未決定へ倒さないためである。

use super::設計関係グラフ;
use crate::{欠落が弱める答え, 設計概念, 設計概念の種類, 設計概念への参照};

/// 設計関係グラフの節点の全件。組み立ての後は変わらない。
#[derive(Debug, Clone, Default)]
pub struct 節点の一覧 {
    概念一覧: Vec<設計概念>,
}

impl 節点の一覧 {
    /// グラフの組み立てが、同じ識別子で同じ種類の概念を1件にまとめた一覧から組む。
    pub(super) fn 生成する(概念一覧: Vec<設計概念>) -> Self {
        Self { 概念一覧 }
    }

    /// 全ての節点。
    pub fn 全件(&self) -> &[設計概念] {
        &self.概念一覧
    }

    /// その参照が指す節点が在るか。識別子と種類の両方が一致する節点だけを在ると答える。
    /// 項から節点を求める工程が、命題が名指した概念の実在をこの問いで確かめる。
    pub fn 在るか(&self, 参照: &設計概念への参照) -> bool {
        self.概念一覧.iter().any(|概念| 概念.参照を貸す() == 参照)
    }

    /// その種類の節点だけを集める。
    pub fn 種類で絞った一覧(&self, 種類: 設計概念の種類) -> Vec<&設計概念> {
        self.概念一覧.iter().filter(|概念| 概念.種類() == 種類).collect()
    }

    /// その参照と名前・所有者の並び・種類が同じで、定義をたどれたかだけが違う節点の一覧。参照が定義をたどれた節点なら空の節点を、空の節点なら定義をたどれた節点を並べる。
    /// 経路の問いが達した節点の先の辺を、不在の問いが端点へ付くはずの辺と分類を、割れた相方の側で探すために使う。
    pub fn 定義をたどれたかだけが違う同じ名前の節点一覧(&self, 参照: &設計概念への参照) -> Vec<&設計概念への参照> {
        let 識別子 = 参照.識別子();
        let 空か = 識別子.Rustの項目でありながら定義をたどれていないか();
        self.概念一覧
            .iter()
            .map(設計概念::参照を貸す)
            .filter(|候補| {
                let 候補の識別子 = 候補.識別子();
                候補.種類() == 参照.種類() && 候補の識別子.名前空間 == 識別子.名前空間 && 候補の識別子.Rustの項目でありながら定義をたどれていないか() != 空か && 候補の識別子.名前 == 識別子.名前 && 候補の識別子.所有者の並び == 識別子.所有者の並び
            })
            .collect()
    }
}

impl 設計関係グラフ {
    /// その参照と同じ名前・同じ所有者の並び・同じ種類で定義をたどれなかった節点のうち、問う答えの種類の辺(主語か目的語として)か分類を持つ最初のもの。
    /// 在るなら、その参照の節点へ付くはずだった辺か分類が空の節点へ付いている見込みがあり、その答えの不在を根拠にできない。
    pub fn 問う答えを持つ定義をたどれなかった同じ名前の節点(&self, 参照: &設計概念への参照, 問う答え一覧: &[欠落が弱める答え]) -> Option<&設計概念への参照> {
        if 参照.識別子().Rustの項目でありながら定義をたどれていないか() {
            return None;
        }
        let 答えを持つか = |空の節点: &設計概念への参照, 答え: 欠落が弱める答え| match 答え {
            欠落が弱める答え::設計関係(種類) => self.関係一覧().iter().any(|関係| 関係.種類 == 種類 && (&関係.主語 == 空の節点 || &関係.目的語 == 空の節点)),
            欠落が弱める答え::プリミティブな関係(種類) => self.プリミティブな関係を貸す().その種類の辺に触れるか(空の節点, 種類),
            欠落が弱める答え::分類 => !self.分類を貸す().概念の分類(空の節点).is_empty(),
        };
        self.節点を貸す()
            .定義をたどれたかだけが違う同じ名前の節点一覧(参照)
            .into_iter()
            .find(|候補| 問う答え一覧.iter().any(|答え| 答えを持つか(*候補, *答え)))
    }

    /// その概念が、主語としても目的語としても1つも設計関係に参加していないか。設計の受理の命題がこの問いを読む。
    /// 数えるのは設計関係の辺だけである。プリミティブな関係はプリミティブの高さの関係であって設計の意味ではなく、分類は辺でないため、
    /// フィールドに持つだけの型もマーカーを実装しただけの型も参加に数えない。
    pub fn 設計関係へ1つも参加していないか(&self, 概念: &設計概念への参照) -> bool {
        !self.関係一覧().iter().any(|関係| &関係.主語 == 概念 || &関係.目的語 == 概念)
    }
}
