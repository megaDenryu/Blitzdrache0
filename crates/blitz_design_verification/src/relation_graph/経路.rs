//! 関係の辺だけを辿る経路の問い。グラフの組み立てと異なり、問い合わせごとに探索する。
//! 設計関係の辺を辿る経路とプリミティブな関係の辺を辿る経路は、辿る辺の高さだけが違い、探索は同じ1つの手順(`辿る`)を通る。
//!
//! **辿る途中の節点が、定義をたどれた節点とモジュールパスが空の節点に割れていたら、経路の不在を根拠にしない。**
//! 抽出器がある表記から型 X の定義をたどれないと、容器 A のフィールド `x: X` の辺は A から空の X へ付き、X から T への辺は定義をたどれた X に付く。
//! 探索は空の X へ達したところで先の辺を見つけられず、A から T への経路が無いと答えてしまう。そこで、達した節点と名前・所有者の並び・種類が同じで
//! 定義をたどれたかだけが違う節点(`定義をたどれたかだけが違う同じ名前の節点一覧`)が辿る種類の出る辺を持つなら、その節点で先を辿れないと答える。
//! 割れた2つの節点を1つへまとめて辿らないのは、空の X が本当にその X かを抽出器が確かめていないためであり、まとめると偽の証明が出うる。
//! 割れていない空の節点(適用範囲の外の型で、定義をたどれた相方が無いもの)は先へ続く辺を持ちえないため、止めない。

use std::collections::HashSet;

use super::設計関係グラフ;
use crate::{プリミティブな関係の種類, 設計概念への参照, 設計関係の種類};

/// 経路の問いの答え。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 経路の答え {
    /// 主語から目的語へ達する経路が在る。
    達する,
    /// 辿れる節点を全部辿っても目的語へ達しない。
    達しない,
    /// 目的語へ達しなかったが、途中の節点が定義をたどれた節点と空の節点に割れており、その先の辺を辿れなかった。持つのは最初に見つけたその節点である。
    割れた節点で先を辿れない(設計概念への参照),
}

impl 経路の答え {
    /// 経路が在ると答えたか。
    pub const fn 達するか(&self) -> bool {
        matches!(self, Self::達する)
    }
}

// 辿る辺の高さと種類。
#[derive(Clone, Copy)]
enum 辿る辺<'a> {
    設計関係(&'a [設計関係の種類]),
    プリミティブな関係(プリミティブな関係の種類),
}

impl 設計関係グラフ {
    /// その関係の種類の辺だけを辿って主語から目的語へ達する経路が在るか。幅優先で辿り、同じ節点を2度は辿らない。
    /// グラフの検証器が「AからBへ依存の経路が存在しない」を問うために要る。
    pub fn 経路が在るか(&self, 主語: &設計概念への参照, 種類の集合: &[設計関係の種類], 目的語: &設計概念への参照) -> 経路の答え {
        self.辿る(主語, 辿る辺::設計関係(種類の集合), 目的語)
    }

    /// その種類のプリミティブな関係の辺だけを辿って主語から目的語へ達する経路が在るか。間接の保持(`旅行者` が `現在地` を持ち、`現在地` が `東西の位置` を持つ)を問うために要る。
    pub fn プリミティブな関係の経路が在るか(&self, 主語: &設計概念への参照, 種類: プリミティブな関係の種類, 目的語: &設計概念への参照) -> 経路の答え {
        self.辿る(主語, 辿る辺::プリミティブな関係(種類), 目的語)
    }

    // 起点から辿る辺だけを辿って目的語へ達するか。済みの鍵を参照そのものにするのは、種類の違う2つの端点が別の辺を持つためである。
    fn 辿る<'a>(&'a self, 主語: &'a 設計概念への参照, 辺: 辿る辺<'_>, 目的語: &設計概念への参照) -> 経路の答え {
        let mut 済み: HashSet<&設計概念への参照> = HashSet::from([主語]);
        let mut 待ち = vec![主語];
        let mut 先を辿れない節点 = None;
        while let Some(いま) = 待ち.pop() {
            if 先を辿れない節点.is_none() && self.相方が先の辺を持つか(いま, 辺) {
                先を辿れない節点 = Some(いま.clone());
            }
            for 次 in self.出る辺の目的語一覧(いま, 辺) {
                if 次 == 目的語 {
                    return 経路の答え::達する;
                }
                if 済み.insert(次) {
                    待ち.push(次);
                }
            }
        }
        先を辿れない節点.map_or(経路の答え::達しない, 経路の答え::割れた節点で先を辿れない)
    }

    // 節点から出る、辿る種類の辺の目的語の一覧。
    fn 出る辺の目的語一覧(&self, いま: &設計概念への参照, 辺: 辿る辺<'_>) -> Vec<&設計概念への参照> {
        match 辺 {
            辿る辺::設計関係(種類の集合) => 種類の集合.iter().flat_map(|種類| self.目的語一覧(いま, *種類)).collect(),
            辿る辺::プリミティブな関係(種類) => self.プリミティブな関係を貸す().出る辺の目的語一覧(いま, 種類),
        }
    }

    // 節点と定義をたどれたかだけが違う同じ名前の節点のどれかが、辿る種類の出る辺を持つか。持つなら、探索はその辺の先を見落としている。
    fn 相方が先の辺を持つか(&self, いま: &設計概念への参照, 辺: 辿る辺<'_>) -> bool {
        self.定義をたどれたかだけが違う同じ名前の節点一覧(いま).into_iter().any(|相方| !self.出る辺の目的語一覧(相方, 辺).is_empty())
    }
}
