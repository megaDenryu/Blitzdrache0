//! 関係の辺だけを辿る経路の問い。グラフの組み立てと異なり、問い合わせごとに探索する。
//! 設計関係の辺を辿る経路と保持する関係の辺を辿る経路は、辿る辺の高さだけが違い、探索は同じ1つの手順を通る。

use std::collections::HashSet;

use super::設計関係グラフ;
use crate::{設計概念への参照, 設計関係の種類};

impl 設計関係グラフ {
    /// その関係の種類の辺だけを辿って主語から目的語へ達する経路が在るか。幅優先で辿り、同じ節点を2度は辿らない。
    /// グラフの検証器が「AからBへ依存の経路が存在しない」を問うために要る。
    pub fn 経路が在るか(&self, 主語: &設計概念への参照, 種類の集合: &[設計関係の種類], 目的語: &設計概念への参照) -> bool {
        辿って達するか(主語, 目的語, |いま| 種類の集合.iter().flat_map(|種類| self.目的語一覧(いま, *種類)).collect())
    }

    /// 保持する関係の辺だけを辿って主語から目的語へ達する経路が在るか。間接の保持(`旅行者` が `現在地` を持ち、`現在地` が `東西の位置` を持つ)を問うために要る。
    pub fn 保持する経路が在るか(&self, 主語: &設計概念への参照, 目的語: &設計概念への参照) -> bool {
        辿って達するか(主語, 目的語, |いま| self.保持する関係一覧.iter().filter(|関係| &関係.主語 == いま).map(|関係| &関係.目的語).collect())
    }
}

// 起点から、次の節点の一覧を答える関数で辿って目的語へ達するか。辿る順と打ち切りは探索が決めるため、次の節点は関数で受ける。
// 済みの鍵を参照そのものにするのは、種類の違う2つの端点が別の辺を持つためである。
fn 辿って達するか<'a>(主語: &'a 設計概念への参照, 目的語: &設計概念への参照, 次の一覧: impl Fn(&設計概念への参照) -> Vec<&'a 設計概念への参照>) -> bool {
    let mut 済み: HashSet<&設計概念への参照> = HashSet::from([主語]);
    let mut 待ち = vec![主語];
    while let Some(いま) = 待ち.pop() {
        for 次 in 次の一覧(いま) {
            if 次 == 目的語 {
                return true;
            }
            if 済み.insert(次) {
                待ち.push(次);
            }
        }
    }
    false
}
