//! 設計関係グラフへの、プリミティブの高さの辺(保持する関係)についての問い。設計関係についての問いは `設計関係の問い` が持つ。

use super::設計関係グラフ;
use crate::{保持する関係, 設計概念への参照};

impl 設計関係グラフ {
    /// 全ての保持する関係。
    pub fn 保持する関係一覧(&self) -> &[保持する関係] {
        &self.保持する関係一覧
    }

    /// 主語が目的語を保持する関係が1件でも在るか。原子命題 `保持する関係が在る` がこの問いに落ちる。
    pub fn 保持する関係が在るか(&self, 主語: &設計概念への参照, 目的語: &設計概念への参照) -> bool {
        self.保持する関係一覧.iter().any(|関係| &関係.主語 == 主語 && &関係.目的語 == 目的語)
    }
}
