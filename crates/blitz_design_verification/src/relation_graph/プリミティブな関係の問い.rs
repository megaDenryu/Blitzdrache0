//! プリミティブな関係の一覧とは、設計関係グラフが持つプリミティブの高さの辺(プリミティブな関係)と、その辺についての問いを持つ部分の型のことである。
//! 設計関係についての問いは `設計関係の問い` が、節点についての問いは `節点の問い` が、辿る経路の問いは `経路` が持つ。
//! 経路の問いをここへ置かないのは、辿る途中の節点が割れているかを見るために節点の一覧が要るためである。
//!
//! 設計関係グラフから切り出したのは、プリミティブな関係の辺だけに触れる問い(在るか・出る辺の目的語)が設計関係の辺にも節点にも触れず、
//! グラフの型に置くとグラフのメソッドが問いの数だけ増えるためである。グラフはこの型を保持し、借りた問いの口を1つだけ持つ。
//! 辺の高さごとに問いを分けるのは、設計関係を問う原子命題がプリミティブな関係を拾わないことを、問いの側の型で保つためでもある。

use crate::{プリミティブな関係, プリミティブな関係の種類, 設計概念への参照};

/// 設計関係グラフのプリミティブな関係の辺の全件。組み立ての後は変わらない。
#[derive(Debug, Clone, Default)]
pub struct プリミティブな関係の一覧 {
    関係一覧: Vec<プリミティブな関係>,
}

impl プリミティブな関係の一覧 {
    /// グラフの組み立てが、端点の節点を持つ辺だけを残した一覧から組む。
    pub(super) fn 生成する(関係一覧: Vec<プリミティブな関係>) -> Self {
        Self { 関係一覧 }
    }

    /// 全てのプリミティブな関係。
    pub fn 全件(&self) -> &[プリミティブな関係] {
        &self.関係一覧
    }

    /// 主語から目的語へその種類のプリミティブな関係が1件でも在るか。原子命題 `プリミティブな関係が在る` がこの問いに落ちる。
    pub fn 在るか(&self, 主語: &設計概念への参照, 種類: プリミティブな関係の種類, 目的語: &設計概念への参照) -> bool {
        self.関係一覧.iter().any(|関係| &関係.主語 == 主語 && 関係.種類 == 種類 && &関係.目的語 == 目的語)
    }

    /// 主語から出るその種類のプリミティブな関係の目的語の一覧。経路の問いがこの一覧を辿る。
    pub fn 出る辺の目的語一覧(&self, 主語: &設計概念への参照, 種類: プリミティブな関係の種類) -> Vec<&設計概念への参照> {
        self.関係一覧.iter().filter(|関係| &関係.主語 == 主語 && 関係.種類 == 種類).map(|関係| &関係.目的語).collect()
    }
}
