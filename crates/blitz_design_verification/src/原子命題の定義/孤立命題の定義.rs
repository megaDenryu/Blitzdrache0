//! 孤立命題とは、その概念が主語としても目的語としても設計関係に1件も参加していないかを問う原子命題のことである。
//!
//! プリミティブな関係と付いているマーカーは参加に数えない。

use super::項;

/// その概念が設計関係へ1つも参加していない、という原子命題。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 孤立命題 {
    概念: 項,
}

impl 孤立命題 {
    /// 孤立しているかを問う対象の概念から組む。
    pub fn 生成する(概念: 項) -> Self {
        Self { 概念 }
    }

    /// 孤立しているかを問う対象の概念。
    pub fn 概念(&self) -> &項 {
        &self.概念
    }

    /// 人が読む1行の表記。
    pub fn 表記(&self) -> String {
        format!("{}は設計関係へ1つも参加していない", self.概念.表記())
    }
}
