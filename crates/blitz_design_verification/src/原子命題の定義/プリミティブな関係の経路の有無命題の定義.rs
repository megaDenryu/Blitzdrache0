//! プリミティブな関係の経路の有無命題とは、主語から目的語へ、その種類のプリミティブな関係のエッジだけを辿って達する経路が在るかを問う原子命題のことである。
//!
//! 直接のエッジ1本も経路の1つとして数える。存在理由の公理が、フィールドとして中に入って一緒に使われる型をたどるためにこの問いを使う。

use super::項;
use crate::プリミティブな関係の種類;

/// 主語から目的語へ、その種類のプリミティブな関係のエッジだけを辿って達する経路が在る、という原子命題。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct プリミティブな関係の経路の有無命題 {
    主語: 項,
    種類: プリミティブな関係の種類,
    目的語: 項,
}

impl プリミティブな関係の経路の有無命題 {
    /// 経路の出どころの主語と、辿ってよい関係の種類と、経路の行き先の目的語から組む。
    pub fn 生成する(主語: 項, 種類: プリミティブな関係の種類, 目的語: 項) -> Self {
        Self { 主語, 種類, 目的語 }
    }

    /// 経路の出どころになる概念。
    pub fn 主語(&self) -> &項 {
        &self.主語
    }

    /// 辿ってよい関係の種類。この種類のエッジだけを辿る。
    pub fn 種類(&self) -> プリミティブな関係の種類 {
        self.種類
    }

    /// 経路の行き先になる概念。
    pub fn 目的語(&self) -> &項 {
        &self.目的語
    }

    /// 人が読む1行の表記。
    pub fn 表記(&self) -> String {
        format!("{}から{}のエッジを辿って{}へ達する経路が在る", self.主語.表記(), self.種類.語(), self.目的語.表記())
    }
}
