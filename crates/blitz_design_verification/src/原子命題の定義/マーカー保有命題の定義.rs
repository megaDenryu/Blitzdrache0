//! マーカー保有命題とは、その型の付いているマーカーがその名前の設計解釈マーカーを含むかを問う原子命題のことである。
//!
//! エッジでなく付いているマーカーを問う。付いているマーカーはマーカーの実装を上位トレイトの宣言で閉じたものであり(`各型に付いているマーカーの一覧`)、
//! `M状態` を実装した型について `M不変データ` を持つかを問えば、直接の実装が無くても成り立つ。
//! 定義域は型の主語と設計解釈マーカーの名前である。トレイト・処理の主語や、`Clone` のような設計解釈マーカーでない名前を問うと、
//! 検証器は偽でなく未決定(問いの定義域の外である)で答える。

use super::項;

/// その型の付いているマーカーが、その名前の設計解釈マーカーを含む、という原子命題。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct マーカー保有命題 {
    概念: 項,
    マーカー名: String,
}

impl マーカー保有命題 {
    /// 問う対象の概念と、設計解釈マーカーの名前から組む。名前は正本のトレイトの名前をそのまま書く。
    pub fn 生成する(概念: 項, マーカー名: &str) -> Self {
        Self {
            概念, マーカー名: マーカー名.to_string()
        }
    }

    /// マーカーを持つかを問う対象の概念。
    pub fn 概念(&self) -> &項 {
        &self.概念
    }

    /// 持つかを問う設計解釈マーカーの名前。
    pub fn マーカー名(&self) -> &str {
        &self.マーカー名
    }

    /// 人が読む1行の表記。
    pub fn 表記(&self) -> String {
        format!("{}は{}を持つ", self.概念.表記(), self.マーカー名)
    }
}
