//! 発生命題とは、その状態遷移でその出来事が成立するかを問う振る舞いの原子命題のことである。
//!
//! 1件の状態遷移についての問いであるため、有限全数の検証器でも数え上げの網羅性は答えに効かない。

use super::項;

/// その状態遷移でそのイベントが成立する、という振る舞いの原子命題。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 発生命題 {
    状態遷移: 項,
    イベント: 項,
}

impl 発生命題 {
    /// 出来事が成立したかを問う1件の状態遷移と、問う出来事から組む。
    pub fn 生成する(状態遷移: 項, イベント: 項) -> Self {
        Self { 状態遷移, イベント }
    }

    /// 出来事が成立したかを問う1件の状態遷移。
    pub fn 状態遷移(&self) -> &項 {
        &self.状態遷移
    }

    /// その状態遷移で成立したかを問う出来事。
    pub fn イベント(&self) -> &項 {
        &self.イベント
    }

    /// 人が読む1行の表記。
    pub fn 表記(&self) -> String {
        format!("{}で{}が発生する", self.状態遷移.表記(), self.イベント.表記())
    }
}
