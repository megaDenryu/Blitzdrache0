//! 状態遷移命題とは、前状態へその入力を与えると後状態へ状態遷移するかを問う振る舞いの原子命題のことである。
//!
//! 有限全数の検証器は、存在の問いではなく、束縛の割り当てが当てている1件の状態遷移についての問いとしてこれを解く。

use super::項;

/// 前状態へその入力を与えると後状態へ状態遷移する、という振る舞いの原子命題。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 状態遷移命題 {
    前状態: 項,
    入力: 項,
    後状態: 項,
}

impl 状態遷移命題 {
    /// 入力を与える前の状態と、与えるコマンドと、与えた後に移るはずの状態から組む。
    pub fn 生成する(前状態: 項, 入力: 項, 後状態: 項) -> Self {
        Self { 前状態, 入力, 後状態 }
    }

    /// 入力を与える前の状態。
    pub fn 前状態(&self) -> &項 {
        &self.前状態
    }

    /// 前状態へ与えるコマンド。
    pub fn 入力(&self) -> &項 {
        &self.入力
    }

    /// 入力を与えた後に移るはずの状態。
    pub fn 後状態(&self) -> &項 {
        &self.後状態
    }

    /// 人が読む1行の表記。
    pub fn 表記(&self) -> String {
        format!("{}へ{}を与えると{}へ状態遷移する", self.前状態.表記(), self.入力.表記(), self.後状態.表記())
    }
}
