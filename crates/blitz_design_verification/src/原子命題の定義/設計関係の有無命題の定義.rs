//! 設計関係の有無命題とは、主語から目的語へその結び付き方の設計関係が1件でも直に在るかを問う原子命題のことである。
//!
//! 宣言の連なりで推移的に成り立つかを問う `設計関係の経路の有無命題` と別の型にするのは、
//! 「この処理はこの型を直に変換用の素材にするか」のように宣言そのものを問う法則がこちらしか使えないためである。

use super::項;
use crate::設計関係の結び付き方;

/// 主語から目的語へその結び付き方の設計関係が1件でも在る、という原子命題。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 設計関係の有無命題 {
    主語: 項,
    結び付き方: 設計関係の結び付き方,
    目的語: 項,
}

impl 設計関係の有無命題 {
    /// 関係の出どころの主語と、問う関係の語と、関係の行き先の目的語から組む。
    pub fn 生成する(主語: 項, 結び付き方: 設計関係の結び付き方, 目的語: 項) -> Self {
        Self { 主語, 結び付き方, 目的語 }
    }

    /// 関係の出どころになる概念。
    pub fn 主語(&self) -> &項 {
        &self.主語
    }

    /// 問う関係の語。
    pub fn 結び付き方(&self) -> 設計関係の結び付き方 {
        self.結び付き方
    }

    /// 関係の行き先になる概念。
    pub fn 目的語(&self) -> &項 {
        &self.目的語
    }

    /// 人が読む1行の表記。
    pub fn 表記(&self) -> String {
        format!("{} {} {}", self.主語.表記(), self.結び付き方.語(), self.目的語.表記())
    }
}
