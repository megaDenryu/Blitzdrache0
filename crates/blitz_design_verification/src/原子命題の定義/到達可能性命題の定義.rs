//! 到達可能性命題とは、その状態が初期状態から到達できるかを問う振る舞いの原子命題のことである。
//!
//! 存在の主張であるため、探索した集合にその状態が在れば網羅していなくても証明済みでよく、無ければ網羅しているときだけ反証済みで答える。

use super::項;

/// その状態が初期状態から到達できる、という振る舞いの原子命題。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 到達可能性命題 {
    状態: 項,
}

impl 到達可能性命題 {
    /// 初期状態から辿り着けるかを問う状態から組む。
    pub fn 生成する(状態: 項) -> Self {
        Self { 状態 }
    }

    /// 初期状態から辿り着けるかを問う状態。
    pub fn 状態(&self) -> &項 {
        &self.状態
    }

    /// 人が読む1行の表記。
    pub fn 表記(&self) -> String {
        format!("{}は到達可能である", self.状態.表記())
    }
}
