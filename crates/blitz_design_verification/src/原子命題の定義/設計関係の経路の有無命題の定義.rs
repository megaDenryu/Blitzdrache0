//! 設計関係の経路の有無命題とは、主語から目的語へ、その結び付き方のエッジだけを辿って達する経路が在るかを問う原子命題のことである。
//!
//! 直接のエッジ1本も経路の1つとして数える。「この型はこの型を間接に保持するか」のように宣言の連なりで成り立つ問いは
//! こちらでしか成り立たず、直に宣言しているかを問う `設計関係の有無命題` と別の型にする。

use super::項;
use crate::設計関係の結び付き方;

/// 主語から目的語へ、その結び付き方のエッジだけを辿って達する経路が在る、という原子命題。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 設計関係の経路の有無命題 {
    主語: 項,
    結び付き方: 設計関係の結び付き方,
    目的語: 項,
}

impl 設計関係の経路の有無命題 {
    /// 経路の出どころの主語と、辿ってよい関係の語と、経路の行き先の目的語から組む。
    pub fn 生成する(主語: 項, 結び付き方: 設計関係の結び付き方, 目的語: 項) -> Self {
        Self { 主語, 結び付き方, 目的語 }
    }

    /// 経路の出どころになる概念。
    pub fn 主語(&self) -> &項 {
        &self.主語
    }

    /// 辿ってよい関係の語。この結び付き方のエッジだけを辿る。
    pub fn 結び付き方(&self) -> 設計関係の結び付き方 {
        self.結び付き方
    }

    /// 経路の行き先になる概念。
    pub fn 目的語(&self) -> &項 {
        &self.目的語
    }

    /// 人が読む1行の表記。
    pub fn 表記(&self) -> String {
        format!("{}から{}のエッジを辿って{}へ達する経路が在る", self.主語.表記(), self.結び付き方.語(), self.目的語.表記())
    }
}
