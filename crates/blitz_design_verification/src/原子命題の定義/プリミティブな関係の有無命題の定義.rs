//! プリミティブな関係の有無命題とは、主語から目的語へその種類のプリミティブな関係が1件でも直に在るかを問う原子命題のことである。
//!
//! 保持するなどのプリミティブな関係はプリミティブの高さの関係であり(Issue #193)、設計の関係だけを問う `設計関係の有無命題` と別の型にする。

use super::項;
use crate::プリミティブな関係の種類;

/// 主語から目的語へその種類のプリミティブな関係が1件でも在る、という原子命題。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct プリミティブな関係の有無命題 {
    主語: 項,
    種類: プリミティブな関係の種類,
    目的語: 項,
}

impl プリミティブな関係の有無命題 {
    /// 関係の出どころの主語と、問う関係の種類と、関係の行き先の目的語から組む。
    pub fn 生成する(主語: 項, 種類: プリミティブな関係の種類, 目的語: 項) -> Self {
        Self { 主語, 種類, 目的語 }
    }

    /// 関係の出どころになる概念。
    pub fn 主語(&self) -> &項 {
        &self.主語
    }

    /// 問う関係の種類。
    pub fn 種類(&self) -> プリミティブな関係の種類 {
        self.種類
    }

    /// 関係の行き先になる概念。
    pub fn 目的語(&self) -> &項 {
        &self.目的語
    }

    /// 人が読む1行の表記。
    pub fn 表記(&self) -> String {
        format!("{} {} {}", self.主語.表記(), self.種類.語(), self.目的語.表記())
    }
}
