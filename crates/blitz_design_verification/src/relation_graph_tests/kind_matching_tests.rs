//! 設計関係グラフへの問いが、端点が名乗る種類を答えへ効かせることを固定する試験。
//!
//! 見ているのは偽陽性の封じである。`トレイト Foo` から1本だけ張った辺を `型 Foo` についての問いが借りて答えると、
//! 実装に無い関係が証明済みになる。したがって辺も節点も、識別子だけでなく種類まで一致する問いにだけ見えなければならない。
//! 種類を照合へ入れた結果として抽出器の推測が外れた辺が問いから消えることは、同一性の衝突と `関係を落とした抽出の欠落` が受け止める。

use crate::{分類の事実, 設計概念, 設計関係の種類, 設計関係グラフ};

use super::{トレイトの参照, 保持する辺, 名前の空間, 型の参照, 辺};

#[test]
fn 割れた節点へ張った辺は種類の違う参照の問いからは見えない() {
    let 結果 = 設計関係グラフ::生成する(
        vec![
            設計概念::型として生成する(名前の空間, "旅行者"),
            設計概念::型として生成する(名前の空間, "現在地"),
            設計概念::トレイトとして生成する(名前の空間, "現在地"),
            設計概念::型として生成する(名前の空間, "東西の位置"),
        ],
        Vec::new(),
        vec![保持する辺("旅行者", "現在地"), 保持する辺("現在地", "東西の位置")],
        分類の事実::無い(),
    );
    assert_eq!(結果.同一性の衝突一覧.len(), 1, "この試験の前提である衝突が1件で起きていない");
    let グラフ = &結果.グラフ;
    assert!(グラフ.保持する関係が在るか(&型の参照("旅行者"), &型の参照("現在地")), "種類の合う問いから辺が見えていない");
    assert!(!グラフ.保持する関係が在るか(&型の参照("旅行者"), &トレイトの参照("現在地")), "型の節点へ張った辺をトレイトの参照の問いが借りている");
    assert!(!グラフ.保持する関係が在るか(&トレイトの参照("現在地"), &型の参照("東西の位置")), "型の節点から出る辺をトレイトの参照の問いが借りている");
    assert!(!グラフ.保持する経路が在るか(&型の参照("旅行者"), &トレイトの参照("現在地")), "種類の違う目的語へ経路が繋がったと答えている");
}

#[test]
fn トレイトから張った辺を同じ名前の型の問いが借りない() {
    // レビューが挙げた偽陽性の形をそのまま題材にする。トレイトFooだけがトレイトMへの辺を持ち、型Fooは1本も辺を持たない。
    let 種類 = 設計関係の種類::参照する;
    let 結果 = 設計関係グラフ::生成する(
        vec![設計概念::型として生成する(名前の空間, "Foo"), 設計概念::トレイトとして生成する(名前の空間, "Foo"), 設計概念::トレイトとして生成する(名前の空間, "M")],
        vec![辺(トレイトの参照("Foo"), 種類, トレイトの参照("M"))],
        Vec::new(),
        分類の事実::無い(),
    );
    let グラフ = &結果.グラフ;
    assert!(グラフ.関係が在るか(&トレイトの参照("Foo"), 種類, &トレイトの参照("M")), "トレイトFooの辺がトレイトFooの問いから見えていない");
    assert!(!グラフ.関係が在るか(&型の参照("Foo"), 種類, &トレイトの参照("M")), "トレイトFooの辺を型Fooの問いが借りている");
    assert!(!グラフ.経路が在るか(&型の参照("Foo"), &[種類], &トレイトの参照("M")), "トレイトFooの辺を型Fooの経路の問いが借りている");
    assert!(グラフ.関係へ1つも参加していないか(&型の参照("Foo")), "1本も辺を持たない型Fooが、同じ名前のトレイトの辺で参加していると答えられている");
}

#[test]
fn 種類の合う節点だけが実在すると答えられる() {
    let 結果 = 設計関係グラフ::生成する(vec![設計概念::トレイトとして生成する(名前の空間, "Foo")], Vec::new(), Vec::new(), 分類の事実::無い());
    let グラフ = &結果.グラフ;
    assert!(グラフ.節点が在るか(&トレイトの参照("Foo")), "在るトレイトの節点を無いと答えている");
    assert!(!グラフ.節点が在るか(&型の参照("Foo")), "同じ名前のトレイトしか無いのに型の節点が在ると答えている");
}
