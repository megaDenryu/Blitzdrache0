//! 設計関係グラフへの、設計の高さのエッジ(設計関係)についての問い。プリミティブな関係についての問いは `プリミティブな関係の問い` が、経路の問いは `経路` が持つ。
//! エッジの高さごとに問いを分けるのは、設計関係を問う原子命題がプリミティブな関係を拾わないことを、問いの側の署名で保つためである。

use super::設計関係グラフ;
use crate::{設計概念への参照, 設計関係の結び付き方};

impl 設計関係グラフ {
    /// その関係が1件でも在るか。命題の原子がこの問いに落ちる。
    pub fn 関係が在るか(&self, 主語: &設計概念への参照, 結び付き方: 設計関係の結び付き方, 目的語: &設計概念への参照) -> bool {
        self.関係一覧.iter().any(|関係| &関係.主語 == 主語 && 関係.結び付き方 == 結び付き方 && &関係.目的語 == 目的語)
    }

    /// 主語と種類を固定したときの目的語の一覧。
    pub fn 目的語一覧(&self, 主語: &設計概念への参照, 結び付き方: 設計関係の結び付き方) -> Vec<&設計概念への参照> {
        self.関係一覧.iter().filter(|関係| &関係.主語 == 主語 && 関係.結び付き方 == 結び付き方).map(|関係| &関係.目的語).collect()
    }

    /// 種類と目的語を固定したときの主語の一覧。
    pub fn 主語一覧(&self, 結び付き方: 設計関係の結び付き方, 目的語: &設計概念への参照) -> Vec<&設計概念への参照> {
        self.関係一覧.iter().filter(|関係| 関係.結び付き方 == 結び付き方 && &関係.目的語 == 目的語).map(|関係| &関係.主語).collect()
    }
}
