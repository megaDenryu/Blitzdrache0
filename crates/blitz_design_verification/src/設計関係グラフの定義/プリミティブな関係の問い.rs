//! プリミティブな関係の一覧とは、設計関係グラフが持つプリミティブの高さのエッジ(プリミティブな関係)と、そのエッジについての問いを持つ部分の型のことである。
//! 設計関係についての問いは `設計関係の問い` が、ノードについての問いは `ノードの問い` が、辿る経路の問いは `経路` が持つ。
//! 経路の問いをここへ置かないのは、辿る途中のノードが割れているかを見るためにノードの一覧が要るためである。
//!
//! 設計関係グラフから切り出したのは、プリミティブな関係のエッジだけに触れる問い(在るか・出るエッジの目的語)が設計関係のエッジにもノードにも触れず、
//! グラフの型に置くとグラフのメソッドが問いの数だけ増えるためである。グラフはこの型を保持し、借りた問いの口を1つだけ持つ。
//! エッジの高さごとに問いを分けるのは、設計関係を問う原子命題がプリミティブな関係を拾わないことを、問いの側の型で保つためでもある。

use crate::{プリミティブな関係の種類, プリミティブな関係エッジ, 設計概念の識別用情報};

/// 設計関係グラフのプリミティブな関係のエッジの全件。組み立ての後は変わらない。
#[derive(Debug, Clone, Default)]
pub struct プリミティブな関係の一覧 {
    関係一覧: Vec<プリミティブな関係エッジ>,
}

impl プリミティブな関係の一覧 {
    /// グラフの組み立てが、端点のノードを持つエッジだけを残した一覧から組む。
    pub(super) fn 生成する(関係一覧: Vec<プリミティブな関係エッジ>) -> Self {
        Self { 関係一覧 }
    }

    /// 全てのプリミティブな関係。
    pub fn 全件(&self) -> &[プリミティブな関係エッジ] {
        &self.関係一覧
    }

    /// 主語から目的語へその種類のプリミティブな関係が1件でも在るか。原子命題 `プリミティブな関係が在る` がこの問いに落ちる。
    pub fn 在るか(&self, 主語: &設計概念の識別用情報, 種類: プリミティブな関係の種類, 目的語: &設計概念の識別用情報) -> bool {
        self.関係一覧.iter().any(|関係| &関係.主語 == 主語 && 関係.種類 == 種類 && &関係.目的語 == 目的語)
    }

    /// そのノードが、その種類のプリミティブな関係の主語か目的語として現れるか。
    pub fn その種類のエッジに触れるか(&self, ノード: &設計概念の識別用情報, 種類: プリミティブな関係の種類) -> bool {
        self.関係一覧.iter().any(|関係| 関係.種類 == 種類 && (&関係.主語 == ノード || &関係.目的語 == ノード))
    }

    /// 主語から出るその種類のプリミティブな関係の目的語の一覧。経路の問いがこの一覧を辿る。
    pub fn 出るエッジの目的語一覧(&self, 主語: &設計概念の識別用情報, 種類: プリミティブな関係の種類) -> Vec<&設計概念の識別用情報> {
        self.関係一覧.iter().filter(|関係| &関係.主語 == 主語 && 関係.種類 == 種類).map(|関係| &関係.目的語).collect()
    }
}
