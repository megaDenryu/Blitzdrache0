//! 関係のエッジだけを辿る経路の問い。グラフの組み立てと異なり、問い合わせごとに探索する。
//! 設計関係のエッジを辿る経路とプリミティブな関係のエッジを辿る経路は、辿るエッジの高さだけが違い、探索は同じ1つの手順(`辿るエッジ::辿る`)を通る。
//! 探索を辿るエッジの型のメソッドにするのは、探索が触れるのが辿るエッジとノードの一覧だけであり、設計関係グラフの全体を借りないためである。
//!
//! **辿る途中のノードが、定義をたどれたノードとモジュールパスが空のノードに割れていたら、経路の不在を根拠にしない。**
//! 抽出器がある表記から型 X の定義をたどれないと、容器 A のフィールド `x: X` のエッジは A から空の X へ付き、X から T へのエッジは定義をたどれた X に付く。
//! 探索は空の X へ達したところで先のエッジを見つけられず、A から T への経路が無いと答えてしまう。そこで、達したノードと名前・所有者の並び・種類が同じで
//! 定義をたどれたかだけが違うノード(`ノードの一覧::定義をたどれたかだけが違う同じ名前のノード一覧`)が辿る種類の出るエッジを持ち、しかもその相方へ探索が達していないなら、そのノードで先を辿れないと答える。
//! 相方へも達していれば、相方の先のエッジは辿り終えているため、止めずに達しないと答える。
//! 割れた2つのノードを1つへまとめて辿らないのは、空の X が本当にその X かを抽出器が確かめていないためであり、まとめると偽の証明が出うる。
//! 割れていない空のノード(適用範囲の外の型で、定義をたどれた相方が無いもの)は先へ続くエッジを持ちえないため、止めない。

use std::collections::HashSet;

use super::{ノードの一覧, プリミティブな関係の一覧, 設計関係グラフ};
use crate::{プリミティブな関係の種類, 設計概念への参照, 設計関係の結び付き方, 設計関係エッジ};

/// 経路の問いの答え。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 経路の答え {
    /// 主語から目的語へ達する経路が在る。
    達する,
    /// 辿れるノードを全部辿っても目的語へ達しない。
    達しない,
    /// 目的語へ達しなかったが、途中のノードが定義をたどれたノードと空のノードに割れており、その先のエッジを辿れなかった。持つのは最初に見つけたそのノードである。
    割れたノードで先を辿れない(設計概念への参照),
}

impl 経路の答え {
    /// 経路が在ると答えたか。
    pub const fn 達するか(&self) -> bool {
        matches!(self, Self::達する)
    }
}

impl 設計関係グラフ {
    /// その結び付き方のエッジだけを辿って主語から目的語へ達する経路が在るか。幅優先で辿り、同じノードを2度は辿らない。
    /// グラフの検証器が「AからBへ依存の経路が存在しない」を問うために要る。
    pub fn 経路が在るか(&self, 主語: &設計概念への参照, 結び付き方の集合: &[設計関係の結び付き方], 目的語: &設計概念への参照) -> 経路の答え {
        辿るエッジ::設計関係 {
            関係一覧: self.関係一覧(), 結び付き方の集合
        }
        .辿る(self.ノードを貸す(), 主語, 目的語)
    }

    /// その種類のプリミティブな関係のエッジだけを辿って主語から目的語へ達する経路が在るか。間接の保持(`旅行者` が `現在地` を持ち、`現在地` が `東西の位置` を持つ)を問うために要る。
    pub fn プリミティブな関係の経路が在るか(&self, 主語: &設計概念への参照, 種類: プリミティブな関係の種類, 目的語: &設計概念への参照) -> 経路の答え {
        辿るエッジ::プリミティブな関係 {
            一覧: self.プリミティブな関係を貸す(), 種類
        }
        .辿る(self.ノードを貸す(), 主語, 目的語)
    }
}

/// 経路の探索が辿るエッジ。エッジの一覧を借り、辿る高さと種類を持つ。
#[derive(Clone, Copy)]
enum 辿るエッジ<'a> {
    設計関係 {
        関係一覧: &'a [設計関係エッジ], 結び付き方の集合: &'a [設計関係の結び付き方]
    },
    プリミティブな関係 {
        一覧: &'a プリミティブな関係の一覧, 種類: プリミティブな関係の種類
    },
}

impl<'a> 辿るエッジ<'a> {
    // 起点からこのエッジだけを辿って目的語へ達するか。済みの鍵を参照そのものにするのは、種類の違う2つの端点が別のエッジを持つためである。
    fn 辿る(self, ノード: &ノードの一覧, 主語: &'a 設計概念への参照, 目的語: &設計概念への参照) -> 経路の答え {
        let mut 済み: HashSet<&設計概念への参照> = HashSet::from([主語]);
        let mut 待ち = vec![主語];
        let mut 割れたノード一覧 = Vec::new();
        while let Some(いま) = 待ち.pop() {
            if self.先のエッジを持つ相方(ノード, いま).next().is_some() {
                割れたノード一覧.push(いま);
            }
            for 次 in self.出るエッジの目的語一覧(いま) {
                if 次 == 目的語 {
                    return 経路の答え::達する;
                }
                if 済み.insert(次) {
                    待ち.push(次);
                }
            }
        }
        // 探索を終えた時点で済みのノードは全部、出るエッジを辿り終えている。相方が済みなら、相方の先は辿った上で目的語へ達しなかったため、止めない。
        割れたノード一覧
            .into_iter()
            .find(|割れた| self.先のエッジを持つ相方(ノード, 割れた).any(|相方| !済み.contains(相方)))
            .map_or(経路の答え::達しない, |割れた| 経路の答え::割れたノードで先を辿れない(割れた.clone()))
    }

    // ノードと定義をたどれたかだけが違う同じ名前の相方のうち、このエッジの出るエッジを持つもの。
    fn 先のエッジを持つ相方<'b>(self, ノード: &'b ノードの一覧, いま: &設計概念への参照) -> impl Iterator<Item = &'b 設計概念への参照> + use<'a, 'b> {
        ノード.定義をたどれたかだけが違う同じ名前のノード一覧(いま).into_iter().filter(move |相方| !self.出るエッジの目的語一覧(相方).is_empty())
    }

    // ノードから出る、このエッジの目的語の一覧。
    fn 出るエッジの目的語一覧(self, いま: &設計概念への参照) -> Vec<&'a 設計概念への参照> {
        match self {
            Self::設計関係 { 関係一覧, 結び付き方の集合 } => 関係一覧.iter().filter(|関係| &関係.主語 == いま && 結び付き方の集合.contains(&関係.結び付き方)).map(|関係| &関係.目的語).collect(),
            Self::プリミティブな関係 { 一覧, 種類 } => 一覧.出るエッジの目的語一覧(いま, 種類),
        }
    }
}
