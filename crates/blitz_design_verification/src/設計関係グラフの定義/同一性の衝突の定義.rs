//! 同一性の衝突とは、同じ設計概念の識別子へ種類の違う設計概念が現れた1件のことである。
//! `設計関係グラフ::生成する` が組み立ての途中で見つけて返し、`関係を落とした抽出の欠落` を通って不在に由来する結果を未決定へ倒す。
//! フィールドを私有にするのは、識別子と2つの種類の組を構造体リテラルで組み替えて、見つけていない衝突を作れないようにするためである。

use crate::{設計概念の種類, 設計概念の識別子};

/// 同じ識別子へ種類の違う概念が現れた1件。先に現れた種類と後から現れた種類の両方を持つ。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 同一性の衝突 {
    識別子: 設計概念の識別子,
    先に現れた種類: 設計概念の種類,
    後から現れた種類: 設計概念の種類,
}

impl 同一性の衝突 {
    /// 衝突した識別子と、先に現れた方の種類と、後から現れた方の種類から衝突を組む。
    pub(super) fn 生成する(識別子: 設計概念の識別子, 先に現れた種類: 設計概念の種類, 後から現れた種類: 設計概念の種類) -> Self {
        Self {
            識別子, 先に現れた種類, 後から現れた種類
        }
    }

    /// 衝突した識別子。
    pub fn 識別子(&self) -> &設計概念の識別子 {
        &self.識別子
    }

    /// 先に現れた方の種類。
    pub const fn 先に現れた種類(&self) -> 設計概念の種類 {
        self.先に現れた種類
    }

    /// 後から現れた方の種類。
    pub const fn 後から現れた種類(&self) -> 設計概念の種類 {
        self.後から現れた種類
    }
}
