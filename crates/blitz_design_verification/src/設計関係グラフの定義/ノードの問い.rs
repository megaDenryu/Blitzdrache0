//! ノードの一覧とは、設計関係グラフが持つノード(設計概念)の全件と、エッジに触れないノードそのものについての問いを持つ部分の型のことである。
//! 設計関係グラフの側には、ノードとエッジの両方に触れる問い(問う答えを持つ、定義をたどれたかだけが違うノード・設計関係への参加)だけを置く。
//! エッジについての問いは `設計関係の問い`・`プリミティブな関係の問い`・`経路` が持つ。
//!
//! 設計関係グラフから切り出したのは、ノードの実在・種類での絞り込み・定義をたどれたかだけが違う同じ名前のノードの問いがエッジに触れず、
//! グラフの型に置くとグラフのメソッドが問いの数だけ増えるためである。グラフはこの型を保持し、借りた問いの口を1つだけ持つ。
//!
//! 定義をたどれずモジュールパスが空のノードは、定義をたどれた同じ名前のノードと別のノードになる。抽出器がある表記や実装の対象から型の定義をたどれなかったとき、
//! その表記から導いたエッジやその実装から読んだ付いているマーカーは空のノードに付き、定義をたどれたノードには付かない。そのため、定義をたどれたノードへの問いは
//! エッジか付いているマーカーの不在を答えてしまう。量化は空のノードも列挙するため、逆に空のノードへの問いが、定義をたどれたノードに付いたエッジの不在を答えることもある。
//! この取り違えを問いの側で止めるため、同じ名前と種類で定義をたどれたかだけが違うノードが、その問いが問う答えの種類のエッジを持つかマーカーが付いているかを答える問いを置く。
//! 答えの種類で絞るのは、空のノードがある種類のエッジしか持たないとき、そのエッジのために、その種類と関係の無い設計関係・保持する・付いているマーカーの問いまで未決定へ倒さないためである。

use super::設計関係グラフ;
use crate::{欠落が弱める答え, 設計概念の種類, 設計概念の識別用情報, 設計概念ノード};

/// 設計関係グラフのノードの全件。組み立ての後は変わらない。
#[derive(Debug, Clone, Default)]
pub struct ノードの一覧 {
    概念一覧: Vec<設計概念ノード>,
}

impl ノードの一覧 {
    /// グラフの組み立てが、同じ識別子で同じ種類の概念を1件にまとめた一覧から組む。
    pub(super) fn 生成する(概念一覧: Vec<設計概念ノード>) -> Self {
        Self { 概念一覧 }
    }

    /// 全てのノード。
    pub fn 全件(&self) -> &[設計概念ノード] {
        &self.概念一覧
    }

    /// その参照が指すノードが在るか。識別子と種類の両方が一致するノードだけを在ると答える。
    /// 項からノードを求める工程が、命題が名指した概念の実在をこの問いで確かめる。
    pub fn 在るか(&self, 参照: &設計概念の識別用情報) -> bool {
        self.概念一覧.iter().any(|概念| 概念.参照を貸す() == 参照)
    }

    /// その種類のノードだけを集める。
    pub fn 種類で絞った一覧(&self, 種類: 設計概念の種類) -> Vec<&設計概念ノード> {
        self.概念一覧.iter().filter(|概念| 概念.種類() == 種類).collect()
    }

    /// その参照と名前・所有者の並び・種類が同じで、定義をたどれたかだけが違うノードの一覧。参照が定義をたどれたノードなら空のノードを、空のノードなら定義をたどれたノードを並べる。
    /// 経路の問いが達したノードの先のエッジを、不在の問いが端点へ付くはずのエッジと付いているマーカーを、割れた相方の側で探すために使う。
    pub fn 定義をたどれたかだけが違う同じ名前のノード一覧(&self, 参照: &設計概念の識別用情報) -> Vec<&設計概念の識別用情報> {
        let 識別子 = 参照.識別子();
        let 空か = 識別子.Rustの項目でありながら定義をたどれていないか();
        self.概念一覧
            .iter()
            .map(設計概念ノード::参照を貸す)
            .filter(|候補| {
                let 候補の識別子 = 候補.識別子();
                候補.種類() == 参照.種類()
                    && 候補の識別子.名前空間() == 識別子.名前空間()
                    && 候補の識別子.Rustの項目でありながら定義をたどれていないか() != 空か
                    && 候補の識別子.名前() == 識別子.名前()
                    && 候補の識別子.所有者の並び() == 識別子.所有者の並び()
            })
            .collect()
    }
}

impl 設計関係グラフ {
    /// その参照と同じ名前・同じ所有者の並び・同じ種類で定義をたどれたかだけが違うノードのうち、問う答えの種類のエッジを(主語か目的語として)持つか、マーカーが付いている最初のもの。
    /// 在るなら、その参照のノードへ付くはずだったエッジか付いているマーカーが相方へ付いている見込みがあり、その答えの不在を根拠にできない。
    /// 左右対称に探すのは、量化が空のノードも列挙するため、問いの端点が空のノードで、エッジが定義をたどれた相方に付いていることがあるからである。
    pub fn 問う答えを持つ定義をたどれたかだけが違う同じ名前のノード(&self, 参照: &設計概念の識別用情報, 問う答え一覧: &[欠落が弱める答え]) -> Option<&設計概念の識別用情報> {
        let 答えを持つか = |相方: &設計概念の識別用情報, 答え: 欠落が弱める答え| match 答え {
            欠落が弱める答え::設計関係(結び付き方) => self.関係一覧().iter().any(|関係| 関係.結び付き方() == 結び付き方 && (関係.主語() == 相方 || 関係.目的語() == 相方)),
            欠落が弱める答え::プリミティブな関係(種類) => self.プリミティブな関係を貸す().その種類のエッジに触れるか(相方, 種類),
            欠落が弱める答え::付いているマーカー => !self.各型に付いているマーカーの一覧を貸す().概念に付いているマーカー(相方).is_empty(),
        };
        self.ノードを貸す()
            .定義をたどれたかだけが違う同じ名前のノード一覧(参照)
            .into_iter()
            .find(|候補| 問う答え一覧.iter().any(|答え| 答えを持つか(候補, *答え)))
    }

    /// その概念が、主語としても目的語としても1つも設計関係に参加していないか。設計の受理の命題がこの問いを読む。
    /// 数えるのは設計関係のエッジだけである。プリミティブな関係はプリミティブの高さの関係であって設計の意味ではなく、付いているマーカーはエッジでないため、
    /// フィールドに持つだけの型もマーカーを実装しただけの型も参加に数えない。
    pub fn 設計関係へ1つも参加していないか(&self, 概念: &設計概念の識別用情報) -> bool {
        !self.関係一覧().iter().any(|関係| 関係.主語() == 概念 || 関係.目的語() == 概念)
    }
}
