//! 抽出した概念の一覧から、同じ識別子で同じ種類の重複を1件にまとめ、同じ識別子で種類が違うものを同一性の衝突として見つける工程。
//! 受け取るのは抽出した概念の一覧であり、返すのは重複を除いた概念の一覧と見つけた衝突の一覧である。種類が違うものは両方をノードとして残す。
//! グラフのエッジも付いているマーカーも読まず、触るのは受け取った概念の一覧だけであるため、グラフの組み立ての本体とは別のファイルに置く。

use std::collections::{HashMap, HashSet, hash_map::Entry};

use super::{同一性の衝突, 設計概念ノード};

/// 重複を除いた概念の一覧と、そのとき見つけた同一性の衝突の一覧の対である。
#[derive(Debug, Clone, Default)]
pub struct 重複を除いた概念一覧と同一性の衝突 {
    /// 同じ識別子で同じ種類の概念を1件にまとめた一覧。先に現れた順を保つ。
    pub 概念一覧: Vec<設計概念ノード>,
    /// 同じ識別子へ種類の違う概念が現れた1件ごとの衝突の一覧。
    pub 衝突一覧: Vec<同一性の衝突>,
}

impl 重複を除いた概念一覧と同一性の衝突 {
    /// 概念の一覧から重複を除き、同一性の衝突を見つける。
    pub fn 概念一覧から生成する(概念一覧: Vec<設計概念ノード>) -> Self {
        let mut 済みの組 = HashSet::new();
        let mut 先に現れた種類 = HashMap::new();
        let mut 重複を除いた概念一覧 = Vec::new();
        let mut 同一性の衝突一覧 = Vec::new();
        for 概念 in 概念一覧 {
            if !済みの組.insert((概念.識別子().clone(), 概念.種類())) {
                continue;
            }
            match 先に現れた種類.entry(概念.識別子().clone()) {
                Entry::Vacant(空き) => {
                    空き.insert(概念.種類());
                }
                Entry::Occupied(先の種類) => 同一性の衝突一覧.push(同一性の衝突::生成する(概念.識別子().clone(), *先の種類.get(), 概念.種類())),
            }
            重複を除いた概念一覧.push(概念);
        }
        Self {
            概念一覧: 重複を除いた概念一覧,
            衝突一覧: 同一性の衝突一覧,
        }
    }
}
