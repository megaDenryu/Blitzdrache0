//! 関係を落とした抽出の欠落とは、設計関係か分類の事実そのものを1件も組めなかった箇所を、理由の呼び名と弱める答えの並びの組ごとの件数で数えたもののことである。
//! 分類の事実を落とすと、ラベルが無いことを「そのマーカーを持っていない」と読んでしまうため、関係を落としたのと同じ扱いにする。
//!
//! この型が在るのは、辺が無いことを根拠にした結果を弱めるためである。抽出器がある行から設計関係を組めなかったとき、
//! その関係はグラフへ入らない。そのグラフへ「その関係が在るか」を問うと答えは否になり、不在を根拠に反証済みを答えると、
//! 否定の下でその反証が反転して証明済みになる。抽出できなかった行を人へ表示することは、この反転を止めない。
//!
//! **このクレートは抽出器を知らない。** したがってこの型は理由を `xtask` の列挙で持たず、人が読む説明の文字列で持つ。
//! 落とした理由をどう区分するかは抽出器の側の判断であり、検証器が問うのは「その答えを弱める件が在るか」と、その件数と説明だけである。
//!
//! **同一性の衝突もこの欠落に数える。** 同じ識別子へ種類の違う概念が現れると節点が2つへ割れ、辺は割れた両方へ散る。
//! 片方の節点へ問うと在るはずの辺が見つからないため、関係を落としたのと同じ帰結になる。
//!
//! **欠落は、落とした件ごとに、どの答えを弱めるかを持つ。** 答えを弱めるのは、その答えを導く事実を落とした件だけである。
//! どの件がどの答えを弱めるかは抽出器が決めて渡す。落とした件がどの事実を読めなかったかを知るのが抽出器だからである。
//! 同一性の衝突と、関係の端点が節点を持たないことは、どの答えの根拠も奪うため全部の答えを弱める。
//! 参照: `_doc/設計/設計オントロジー.md` 第6節・第9節。

use super::欠落が弱める答えの定義::欠落が弱める答え;
use super::設計関係グラフの定義::同一性の衝突;

/// 関係を落とした理由1件ぶんの、人が読む説明とその件数。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 落とした理由ごとの件数 {
    /// 人が読む理由の説明。未決定の理由の文がこれを並べる。
    pub 理由の説明: String,
    /// その理由で関係を落とした件数。
    pub 件数: usize,
    /// その理由の件が不在を根拠にできなくする答えの並び。
    pub 弱める答え一覧: Vec<欠落が弱める答え>,
}

/// 設計関係そのものを落とした箇所を、理由の呼び名と弱める答えの並びの組ごとの件数で数えたもの。同じ呼び名でも弱める答えが違えば別の件である。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct 関係を落とした抽出の欠落 {
    理由ごとの件数: Vec<落とした理由ごとの件数>,
}

impl 関係を落とした抽出の欠落 {
    /// グラフの組み立てが見つけた、節点を持たない端点を欠落へ加える。
    pub fn グラフの端点を検査する(mut self, グラフ: &crate::設計関係グラフ) -> Self {
        let 件数 = グラフ.節点が無い端点一覧().len();
        self.理由ごとの件数.retain(|件| 件.理由の説明 != "関係の端点と識別子・種類が一致する節点が無い");
        if 件数 > 0 {
            self.理由ごとの件数.push(落とした理由ごとの件数 {
                理由の説明: "関係の端点と識別子・種類が一致する節点が無い".to_string(),
                件数,
                弱める答え一覧: 欠落が弱める答え::全部(),
            });
        }
        self
    }
    /// 関係を1件も落としていないことを表す欠落。抽出器を通さない試験がこれを渡す。
    pub fn 無い() -> Self {
        Self::default()
    }

    /// 理由ごとの件数と同一性の衝突の一覧から組む。件数が0件の理由は落とした事実を持たないため捨てる。
    /// 衝突を1件ずつ数えずに1つの理由へまとめるのは、検証器が読むのが理由の説明と件数だけであり、衝突した識別子まで運ぶ必要が無いためである。
    pub fn 生成する(理由ごとの件数: Vec<落とした理由ごとの件数>, 同一性の衝突一覧: &[同一性の衝突]) -> Self {
        let mut 一覧: Vec<落とした理由ごとの件数> = 理由ごとの件数.into_iter().filter(|件| 件.件数 > 0).collect();
        if !同一性の衝突一覧.is_empty() {
            一覧.push(落とした理由ごとの件数 {
                理由の説明: "同じ識別子へ種類の違う概念が現れ、節点が2つへ割れた".to_string(),
                件数: 同一性の衝突一覧.len(),
                弱める答え一覧: 欠落が弱める答え::全部(),
            });
        }
        Self { 理由ごとの件数: 一覧 }
    }

    /// 関係を落とした件が1件でも在るか。どの答えを弱めるかを問わない。原子の答えを弱めるか、対象集合の列挙を全件と呼ぶかは、答えの並びを受け取る `どれかの答えを弱めるか` が決める。
    pub fn 在るか(&self) -> bool {
        !self.理由ごとの件数.is_empty()
    }

    /// 並べた答えのどれかを弱める件が1件でも在るか。不在を根拠にした原子の答えを弱めるかどうかをこの問いが決める。
    pub fn どれかの答えを弱めるか(&self, 答え一覧: &[欠落が弱める答え]) -> bool {
        self.理由ごとの件数.iter().any(|件| 件.弱める答え一覧.iter().any(|答え| 答え一覧.contains(答え)))
    }

    /// 並べた答えのどれかを弱める件だけを並べた、人が読む1行。弱めた答えの未決定の理由がこれを出し、無関係な件で読み手を惑わせない。
    pub fn 答えを弱める件の説明(&self, 答え一覧: &[欠落が弱める答え]) -> String {
        let 内訳: Vec<String> = self.理由ごとの件数.iter().filter(|件| 件.弱める答え一覧.iter().any(|答え| 答え一覧.contains(答え))).map(落とした理由ごとの件数::表記).collect();
        let 語一覧: Vec<&str> = 答え一覧.iter().map(|答え| 答え.語()).collect();
        format!("{}の答えを弱める抽出の欠落が在る({})", 語一覧.join("・"), 内訳.join("、"))
    }

    /// 並べた答えのどれかを弱める件の件数の合計。設計の検証の合否が、命題の集合が問う答えを弱める件だけを数えるために使う。
    pub fn 答えを弱める件の件数(&self, 答え一覧: &[欠落が弱める答え]) -> usize {
        self.理由ごとの件数.iter().filter(|件| 件.弱める答え一覧.iter().any(|答え| 答え一覧.contains(答え))).map(|件| 件.件数).sum()
    }

    /// 落とした件数の合計。
    pub fn 合計の件数(&self) -> usize {
        self.理由ごとの件数.iter().map(|件| 件.件数).sum()
    }

    /// 人が読む1行。未決定の理由の説明と、抽出の内訳の表示がこれを並べ、読み手が何件どういう理由で落ちたかを追えるようにする。
    /// 0件のときも文を返すのは、検査器が検査した件数を必ず報告するためである
    /// (グローバルCLAUDE.md「検査器は解析できなかった入力を黙って対象から外してはならない」)。
    pub fn 説明(&self) -> String {
        if self.理由ごとの件数.is_empty() {
            return "関係を落とした抽出の欠落は0件である".to_string();
        }
        let 内訳: Vec<String> = self.理由ごとの件数.iter().map(落とした理由ごとの件数::表記).collect();
        format!("関係を落とした抽出の欠落が{}件在る({})", self.合計の件数(), 内訳.join("、"))
    }
}

impl 落とした理由ごとの件数 {
    /// 人が読む1項目。同じ呼び名の件が弱める答えの違いで2つ並びうるため、弱める答えの語を添えて見分けられるようにする。
    fn 表記(&self) -> String {
        let 語一覧: Vec<&str> = self.弱める答え一覧.iter().map(|答え| 答え.語()).collect();
        format!("{}: {}件(弱める答え: {})", self.理由の説明, self.件数, 語一覧.join("・"))
    }
}
