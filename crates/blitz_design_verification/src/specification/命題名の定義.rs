//! 命題名とは、命題の集合の中で1つの命題を指す名前のことである。命題の集合そのものの名前もこの型で持つ。
//!
//! 裸の文字列で持たないのは、集計の報告がどの命題が反証されたかをこの名前で指し、命題の表記や反例の説明の文と取り違えても型が通るのを止めるためである。

/// 命題の集合の中で1つの命題を指す名前。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct 命題名(String);

impl 命題名 {
    /// 名前の文字列から組む。
    pub fn 生成する(名前: &str) -> Self {
        Self(名前.to_string())
    }

    /// 人が読む名前の文字列。報告の行へ書き出す境界がこれを読む。
    pub fn 文字列(&self) -> &str {
        &self.0
    }
}
