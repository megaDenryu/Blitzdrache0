//! 命題の集合の集計が、3つの結果を取り違えずに数えることを固定する試験。
//!
//! 未決定を反証済みへ混ぜる書き換えをここが落とす。件数の照合だけでなく反証済みの一覧の中身も見るのは、
//! 件数だけを見ると「未決定を一覧へ積みながら件数は未決定で数える」という中途の壊れ方が通るためである。

use crate::{原子命題, 反例, 名前付きの命題, 命題, 命題の検証器, 命題の集合, 未決定の理由, 検証の方式, 検証結果, 設計概念への参照, 証拠, 項};

/// 反証済みで答えるときの説明。検証器が答える説明と試験が確かめる説明を1つの値にするため、定数へ置く。
const 反証済みで答えるときの説明: &str = "試験の検証器が反例を答えた";

/// 命題が名指した状態の名前で結果を決める検証器。1つの命題の集合の中で3つの結果を作り分けるために置く。
struct 名指した状態の名前で結果を決める検証器;

impl 命題の検証器 for 名指した状態の名前で結果を決める検証器 {
    fn 検証する(&self, 命題: &命題) -> 検証結果 {
        let 命題::原子(原子命題::到達可能である { 状態: 項::名指した概念(参照) }) = 命題 else {
            panic!("試験の命題は到達可能であるの原子1つでなければならない");
        };
        match 参照.識別子().名前.as_str() {
            "証明済みで答える状態" => 検証結果::証明済み(証拠 {
                方式: 検証の方式::有限全数,
                見た対象の件数: 1,
                説明: "試験の検証器が成立を答えた".to_string(),
            }),
            "反証済みで答える状態" => 検証結果::反証済み(反例 {
                方式: 検証の方式::有限全数,
                説明: 反証済みで答えるときの説明.to_string(),
                再現の材料: vec![("状態".to_string(), 参照.表記())],
            }),
            _ => 検証結果::未決定(未決定の理由::この検証器が扱わない式を含む("試験の検証器".to_string())),
        }
    }
}

fn 到達可能である命題(状態の名前: &str) -> 命題 {
    命題::原子から組む(原子命題::到達可能である {
        状態: 項::名指した概念(設計概念への参照::型として生成する("blitz_esca::traveler", 状態の名前)),
    })
}

/// 検証器へ3つの結果を1件ずつ答えさせる命題の集合。
fn 三つの結果を答えさせる命題の集合() -> 命題の集合 {
    命題の集合::生成する(
        "試験の命題の集合",
        vec![
            名前付きの命題::生成する("証明済みになる命題", 到達可能である命題("証明済みで答える状態")),
            名前付きの命題::生成する("反証済みになる命題", 到達可能である命題("反証済みで答える状態")),
            名前付きの命題::生成する("未決定になる命題", 到達可能である命題("未決定で答える状態")),
        ],
    )
}

#[test]
fn 全件を検証すると3つの結果を1件ずつ数える() {
    let 集計 = 三つの結果を答えさせる命題の集合().全件を検証する(&名指した状態の名前で結果を決める検証器);
    assert_eq!(集計.証明済みの件数, 1, "証明済みの件数が1件でない: {}", 集計.表記());
    assert_eq!(集計.反証済みの件数, 1, "反証済みの件数が1件でない: {}", 集計.表記());
    assert_eq!(集計.未決定の件数, 1, "未決定の件数が1件でない: {}", 集計.表記());
}

#[test]
fn 反証済みの一覧は反証済みの命題の名前と反例だけを持つ() {
    let 集計 = 三つの結果を答えさせる命題の集合().全件を検証する(&名指した状態の名前で結果を決める検証器);
    let [(名前, 見つけた反例)] = 集計.反証済みの一覧.as_slice() else {
        panic!("反証済みの一覧が1件でない(未決定が混ざっていないか): {}件", 集計.反証済みの一覧.len());
    };
    assert_eq!(名前, "反証済みになる命題");
    assert_eq!(見つけた反例.説明, 反証済みで答えるときの説明);
}

#[test]
fn 未決定の一覧は未決定の命題の名前と理由だけを持つ() {
    let 集計 = 三つの結果を答えさせる命題の集合().全件を検証する(&名指した状態の名前で結果を決める検証器);
    let [(名前, 見つけた理由)] = 集計.未決定の一覧.as_slice() else {
        panic!("未決定の一覧が1件でない(反証済みが混ざっていないか): {}件", 集計.未決定の一覧.len());
    };
    assert_eq!(名前, "未決定になる命題");
    assert!(matches!(見つけた理由, 未決定の理由::この検証器が扱わない式を含む(_)), "未決定の理由が運ばれていない: {見つけた理由:?}");
}

#[test]
fn 空の命題の集合は3つとも0件で答える() {
    let 集計 = 命題の集合::生成する("空の命題の集合", Vec::new()).全件を検証する(&名指した状態の名前で結果を決める検証器);
    assert_eq!(集計.証明済みの件数, 0, "空の集合で証明済みが0件でない: {}", 集計.表記());
    assert_eq!(集計.反証済みの件数, 0, "空の集合で反証済みが0件でない: {}", 集計.表記());
    assert_eq!(集計.未決定の件数, 0, "空の集合で未決定が0件でない: {}", 集計.表記());
    assert!(集計.反証済みの一覧.is_empty(), "空の集合で反証済みの一覧が空でない");
    assert!(集計.未決定の一覧.is_empty(), "空の集合で未決定の一覧が空でない");
}
