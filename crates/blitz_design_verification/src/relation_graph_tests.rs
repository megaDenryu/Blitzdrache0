//! 設計関係グラフの組み立てが、同じ識別子で現れた概念をどう扱うかを固定する試験と、子モジュールが共有する小さな辺の組み立て。
//!
//! この親が固定するのは2つである。同じ識別子で同じ種類の概念を1件へまとめること。種類が違うものをまとめず両方を節点として残し、
//! 1件ごとを衝突として数えることである。**グラフへの問いが端点の種類を答えへ効かせることは子モジュール `kind_matching_tests` が固定する。**
//! 組み立ての規則と問いの照合を別のモジュールにするのは、前者が節点のまとめ方の判断であり、後者が辺と節点の探し方の判断であるためである。

mod kind_matching_tests;

use std::path::PathBuf;

use crate::{
    保持する関係, 分類の事実, 導出の根拠, 抽出の出どころ, 抽出元の構文, 設計概念, 設計概念の種類, 設計概念の識別子, 設計概念への参照, 設計関係, 設計関係の種類, 設計関係グラフ
};

const 名前の空間: &str = "blitz_esca::traveler";

fn 識別子(名前: &str) -> 設計概念の識別子 {
    設計概念の識別子::Rustの項目として生成する(名前の空間, 名前)
}

fn 型の参照(名前: &str) -> 設計概念への参照 {
    設計概念への参照::型として生成する(名前の空間, 名前)
}

fn トレイトの参照(名前: &str) -> 設計概念への参照 {
    設計概念への参照::トレイトとして生成する(名前の空間, 名前)
}

fn 出どころ(構文: 抽出元の構文) -> 抽出の出どころ {
    抽出の出どころ {
        パス: PathBuf::from("crates/blitz_esca/src/traveler.rs"),
        行番号: 1,
        構文,
    }
}

fn 保持する辺(主語: &str, 目的語: &str) -> 保持する関係 {
    保持する関係 {
        主語: 型の参照(主語),
        目的語: 型の参照(目的語),
        出どころ: 出どころ(抽出元の構文::構造体のフィールド),
        根拠: 導出の根拠::生成する("試験が定義の式を通さずに直に置いた関係", Vec::new()),
    }
}

fn 辺(主語: 設計概念への参照, 種類: 設計関係の種類, 目的語: 設計概念への参照) -> 設計関係 {
    設計関係 {
        主語,
        種類,
        目的語,
        出どころ: 出どころ(抽出元の構文::関数の役割の型引数),
        根拠: 導出の根拠::生成する("試験が定義の式を通さずに直に置いた関係", Vec::new()),
    }
}

#[test]
fn 同じ識別子で同じ種類の概念は1件へまとめ衝突に数えない() {
    let 結果 = 設計関係グラフ::生成する(vec![設計概念::型として生成する(名前の空間, "旅行者"), 設計概念::型として生成する(名前の空間, "旅行者")], Vec::new(), Vec::new(), 分類の事実::無い());
    assert_eq!(結果.グラフ.概念一覧().len(), 1, "同じ識別子で同じ種類の概念が1件へまとめられていない");
    assert!(結果.同一性の衝突一覧.is_empty(), "種類が同じなのに衝突として数えている: {:?}", 結果.同一性の衝突一覧);
}

#[test]
fn 同じ識別子で種類が違う概念はまとめず衝突を1件数える() {
    let 結果 = 設計関係グラフ::生成する(
        vec![設計概念::型として生成する(名前の空間, "旅行者"), 設計概念::トレイトとして生成する(名前の空間, "旅行者")],
        Vec::new(),
        Vec::new(),
        分類の事実::無い(),
    );
    assert_eq!(結果.グラフ.概念一覧().len(), 2, "種類の違う概念が黙って1節点へまとめられている");
    assert_eq!(結果.同一性の衝突一覧.len(), 1, "同一性の衝突が数えられていない");
    let 衝突 = &結果.同一性の衝突一覧[0];
    assert_eq!(衝突.識別子, 識別子("旅行者"));
    assert_eq!(衝突.先に現れた種類, 設計概念の種類::型);
    assert_eq!(衝突.後から現れた種類, 設計概念の種類::トレイト);
}
