//! 設計関係グラフの組み立てが、同一性の衝突をどう扱うかを固定する試験。
//!
//! 固定するのは3つである。同じ識別子で同じ種類の概念を1件へ畳むこと。種類が違うものを畳まず両方を節点として残し、
//! 1件ごとを衝突として数えること。そして**割れた結果として辺が散らないこと**である。
//! 3つ目を見るのは、畳みをやめたことで「黙って1節点へ畳む」が「黙って辺が2つの節点へ分かれる」へ置き換わっていないかを
//! 確かめるためである。辺は識別子で張られるため、節点の種類が割れても関係の問いと経路の問いの答えは変わらない。

use std::path::PathBuf;

use crate::{抽出の出どころ, 抽出元の構文, 設計概念, 設計概念の種類, 設計概念の識別子, 設計関係, 設計関係の種類, 設計関係グラフ};

const 名前の空間: &str = "blitz_esca::traveler";

fn 識別子(名前: &str) -> 設計概念の識別子 {
    設計概念の識別子::Rustの項目として生成する(名前の空間, 名前)
}

fn 保持する辺(主語: &str, 目的語: &str) -> 設計関係 {
    設計関係 {
        主語: 識別子(主語),
        種類: 設計関係の種類::保持する,
        目的語: 識別子(目的語),
        出どころ: 抽出の出どころ {
            パス: PathBuf::from("crates/blitz_esca/src/traveler.rs"),
            行番号: 1,
            構文: 抽出元の構文::構造体のフィールド,
        },
    }
}

#[test]
fn 同じ識別子で同じ種類の概念は1件へ畳み衝突に数えない() {
    let 結末 = 設計関係グラフ::生成する(vec![設計概念::型として生成する(名前の空間, "旅行者"), 設計概念::型として生成する(名前の空間, "旅行者")], Vec::new());
    assert_eq!(結末.グラフ.概念一覧().len(), 1, "同じ識別子で同じ種類の概念が畳まれていない");
    assert!(結末.同一性の衝突一覧.is_empty(), "種類が同じなのに衝突として数えている: {:?}", 結末.同一性の衝突一覧);
}

#[test]
fn 同じ識別子で種類が違う概念は畳まず衝突を1件数える() {
    let 結末 = 設計関係グラフ::生成する(vec![設計概念::型として生成する(名前の空間, "旅行者"), 設計概念::トレイトとして生成する(名前の空間, "旅行者")], Vec::new());
    assert_eq!(結末.グラフ.概念一覧().len(), 2, "種類の違う概念が黙って1節点へ畳まれている");
    assert_eq!(結末.同一性の衝突一覧.len(), 1, "同一性の衝突が数えられていない");
    let 衝突 = &結末.同一性の衝突一覧[0];
    assert_eq!(衝突.識別子, 識別子("旅行者"));
    assert_eq!(衝突.先に現れた種類, 設計概念の種類::型);
    assert_eq!(衝突.後から現れた種類, 設計概念の種類::トレイト);
}

#[test]
fn 割れた節点へ別々に張った辺は関係の問いからも経路の問いからも見える() {
    let 結末 = 設計関係グラフ::生成する(
        vec![
            設計概念::型として生成する(名前の空間, "旅行者"),
            設計概念::型として生成する(名前の空間, "現在地"),
            設計概念::トレイトとして生成する(名前の空間, "現在地"),
            設計概念::型として生成する(名前の空間, "東西の位置"),
        ],
        vec![保持する辺("旅行者", "現在地"), 保持する辺("現在地", "東西の位置")],
    );
    assert_eq!(結末.同一性の衝突一覧.len(), 1, "この試験の前提である衝突が1件で起きていない");
    let グラフ = &結末.グラフ;
    assert!(グラフ.関係が在るか(&識別子("旅行者"), 設計関係の種類::保持する, &識別子("現在地")), "割れた節点へ入る辺が見えていない");
    assert!(グラフ.関係が在るか(&識別子("現在地"), 設計関係の種類::保持する, &識別子("東西の位置")), "割れた節点から出る辺が見えていない");
    assert!(グラフ.経路が在るか(&識別子("旅行者"), &[設計関係の種類::保持する], &識別子("東西の位置")), "割れた節点を通る経路が繋がっていない");
}
