//! 設計関係グラフの組み立てが、同じ識別子で現れた概念をどう扱うかを固定する試験と、子モジュールが共有する小さな辺の組み立て。
//!
//! この親が固定するのは2つである。同じ識別子で同じ種類の概念を1件へ畳むこと。種類が違うものを畳まず両方を節点として残し、
//! 1件ごとを衝突として数えることである。**グラフへの問いが端点の種類を答えへ効かせることは子モジュール `kind_matching_tests` が固定する。**
//! 組み立ての規則と問いの照合を別のモジュールにするのは、前者が節点の畳み方の判断であり、後者が辺と節点の探し方の判断であるためである。

mod kind_matching_tests;

use std::path::PathBuf;

use crate::{抽出の出どころ, 抽出元の構文, 設計概念, 設計概念の種類, 設計概念の識別子, 設計概念への参照, 設計関係, 設計関係の種類, 設計関係グラフ};

const 名前の空間: &str = "blitz_esca::traveler";

fn 識別子(名前: &str) -> 設計概念の識別子 {
    設計概念の識別子::Rustの項目として生成する(名前の空間, 名前)
}

fn 型の参照(名前: &str) -> 設計概念への参照 {
    設計概念への参照::型として生成する(名前の空間, 名前)
}

fn トレイトの参照(名前: &str) -> 設計概念への参照 {
    設計概念への参照::トレイトとして生成する(名前の空間, 名前)
}

fn 保持する辺(主語: &str, 目的語: &str) -> 設計関係 {
    辺(型の参照(主語), 設計関係の種類::保持する, 型の参照(目的語))
}

fn 下位型である辺(主語: 設計概念への参照, 目的語: 設計概念への参照) -> 設計関係 {
    辺(主語, 設計関係の種類::下位型である, 目的語)
}

fn 辺(主語: 設計概念への参照, 種類: 設計関係の種類, 目的語: 設計概念への参照) -> 設計関係 {
    設計関係 {
        主語,
        種類,
        目的語,
        出どころ: 抽出の出どころ {
            パス: PathBuf::from("crates/blitz_esca/src/traveler.rs"),
            行番号: 1,
            構文: 抽出元の構文::構造体のフィールド,
        },
    }
}

#[test]
fn 同じ識別子で同じ種類の概念は1件へ畳み衝突に数えない() {
    let 結末 = 設計関係グラフ::生成する(vec![設計概念::型として生成する(名前の空間, "旅行者"), 設計概念::型として生成する(名前の空間, "旅行者")], Vec::new());
    assert_eq!(結末.グラフ.概念一覧().len(), 1, "同じ識別子で同じ種類の概念が畳まれていない");
    assert!(結末.同一性の衝突一覧.is_empty(), "種類が同じなのに衝突として数えている: {:?}", 結末.同一性の衝突一覧);
}

#[test]
fn 同じ識別子で種類が違う概念は畳まず衝突を1件数える() {
    let 結末 = 設計関係グラフ::生成する(vec![設計概念::型として生成する(名前の空間, "旅行者"), 設計概念::トレイトとして生成する(名前の空間, "旅行者")], Vec::new());
    assert_eq!(結末.グラフ.概念一覧().len(), 2, "種類の違う概念が黙って1節点へ畳まれている");
    assert_eq!(結末.同一性の衝突一覧.len(), 1, "同一性の衝突が数えられていない");
    let 衝突 = &結末.同一性の衝突一覧[0];
    assert_eq!(衝突.識別子, 識別子("旅行者"));
    assert_eq!(衝突.先に現れた種類, 設計概念の種類::型);
    assert_eq!(衝突.後から現れた種類, 設計概念の種類::トレイト);
}
