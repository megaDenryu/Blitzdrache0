//! 設計関係グラフの組み立てが同じ識別子で現れた概念をどう扱うかと、設計関係への参加の問いが何を数えるかを固定する試験と、子モジュールが共有する小さなエッジの組み立て。
//!
//! この親が固定するのは3つである。同じ識別子で同じ種類の概念を1件へまとめること。種類が違うものをまとめず両方をノードとして残し、
//! 1件ごとを衝突として数えること。設計関係への参加の問いが設計関係のエッジだけを数え、保持する関係のエッジを数えないことである。**グラフへの問いが端点の種類を答えへ効かせることは子モジュール `kind_matching_tests` が固定する。**
//! 組み立ての規則と問いの照合を別のモジュールにするのは、前者がノードのまとめ方の判断であり、後者がエッジとノードの探し方の判断であるためである。

#[path = "設計関係グラフの試験/種類まで照合する試験.rs"]
mod 種類まで照合する試験;

use std::path::PathBuf;

use crate::{
    プリミティブな関係の種類, プリミティブな関係エッジ, 導出の根拠, 抽出の出どころ, 抽出元の構文, 設計概念の種類, 設計概念の識別子, 設計概念の識別用情報, 設計概念ノード, 設計解釈マーカーの宣言の一覧, 設計関係の結び付き方, 設計関係エッジ,
    設計関係グラフ,
};

const 名前の空間: &str = "blitz_esca::traveler";

fn 識別子(名前: &str) -> 設計概念の識別子 {
    設計概念の識別子::Rustの項目として生成する(名前の空間, 名前)
}

fn 型の参照(名前: &str) -> 設計概念の識別用情報 {
    設計概念の識別用情報::型として生成する(名前の空間, 名前)
}

fn トレイトの参照(名前: &str) -> 設計概念の識別用情報 {
    設計概念の識別用情報::トレイトとして生成する(名前の空間, 名前)
}

fn 出どころ(構文: 抽出元の構文) -> 抽出の出どころ {
    抽出の出どころ {
        パス: PathBuf::from("crates/blitz_esca/src/traveler.rs"),
        行番号: 1,
        構文,
    }
}

fn 保持するエッジ(主語: &str, 目的語: &str) -> プリミティブな関係エッジ {
    プリミティブな関係エッジ {
        主語: 型の参照(主語),
        種類: プリミティブな関係の種類::保持する,
        目的語: 型の参照(目的語),
        出どころ: 出どころ(抽出元の構文::構造体のフィールド),
        根拠: 導出の根拠::生成する("試験が定義の式を通さずに直に置いた関係", Vec::new()),
    }
}

fn エッジ(主語: 設計概念の識別用情報, 結び付き方: 設計関係の結び付き方, 目的語: 設計概念の識別用情報) -> 設計関係エッジ {
    設計関係エッジ {
        主語,
        結び付き方,
        目的語,
        出どころ: 出どころ(抽出元の構文::関数の役割の型引数),
        根拠: 導出の根拠::生成する("試験が定義の式を通さずに直に置いた関係", Vec::new()),
    }
}

#[test]
fn 同じ識別子で同じ種類の概念は1件へまとめ衝突に数えない() {
    let 結果 = 設計関係グラフ::生成する(
        vec![設計概念ノード::型として生成する(名前の空間, "旅行者"), 設計概念ノード::型として生成する(名前の空間, "旅行者")],
        Vec::new(),
        Vec::new(),
        設計解釈マーカーの宣言の一覧::無い(),
    );
    assert_eq!(結果.グラフ.概念一覧().len(), 1, "同じ識別子で同じ種類の概念が1件へまとめられていない");
    assert!(結果.同一性の衝突一覧.is_empty(), "種類が同じなのに衝突として数えている: {:?}", 結果.同一性の衝突一覧);
}

#[test]
fn 同じ識別子で種類が違う概念はまとめず衝突を1件数える() {
    let 結果 = 設計関係グラフ::生成する(
        vec![設計概念ノード::型として生成する(名前の空間, "旅行者"), 設計概念ノード::トレイトとして生成する(名前の空間, "旅行者")],
        Vec::new(),
        Vec::new(),
        設計解釈マーカーの宣言の一覧::無い(),
    );
    assert_eq!(結果.グラフ.概念一覧().len(), 2, "種類の違う概念が黙って1ノードへまとめられている");
    assert_eq!(結果.同一性の衝突一覧.len(), 1, "同一性の衝突が数えられていない");
    let 衝突 = &結果.同一性の衝突一覧[0];
    assert_eq!(衝突.識別子(), &識別子("旅行者"));
    assert_eq!(衝突.先に現れた種類(), 設計概念の種類::型);
    assert_eq!(衝突.後から現れた種類(), 設計概念の種類::トレイト);
}

#[test]
fn 設計関係への参加は設計関係のエッジだけを数え保持する関係のエッジを数えない() {
    let 結果 = 設計関係グラフ::生成する(
        ["旅行者", "旅行者ID", "現在地"].map(|名前| 設計概念ノード::型として生成する(名前の空間, 名前)).to_vec(),
        vec![エッジ(型の参照("旅行者ID"), 設計関係の結び付き方::識別する, 型の参照("旅行者"))],
        vec![保持するエッジ("旅行者", "旅行者ID"), 保持するエッジ("旅行者", "現在地")],
        設計解釈マーカーの宣言の一覧::無い(),
    );
    let グラフ = &結果.グラフ;
    assert!(!グラフ.設計関係へ1つも参加していないか(&型の参照("旅行者")), "識別するの目的語である旅行者を参加していないと答えた");
    assert!(!グラフ.設計関係へ1つも参加していないか(&型の参照("旅行者ID")), "識別するの主語である旅行者IDを参加していないと答えた");
    assert!(グラフ.設計関係へ1つも参加していないか(&型の参照("現在地")), "保持する関係の目的語でしかない現在地を参加に数えた");
    assert!(
        グラフ.プリミティブな関係を貸す().在るか(&型の参照("旅行者"), プリミティブな関係の種類::保持する, &型の参照("現在地")),
        "参加に数えない保持する関係のエッジがグラフから消えている"
    );
}
