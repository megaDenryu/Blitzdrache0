/// 列挙してよい対象の件数の上限。1件ごとに命題の本体を解き直すため、これを超えると1回の検証が人が待てる時間を超える。
/// 上限で切ったときは未決定で答えるため、超えたことが黙って通り過ぎることは無い。
const 列挙してよい対象の上限: usize = 100_000;

/// 遷移モデルと数え上げの網羅性を保持し、振る舞いの原子命題と到達可能な対象集合を解く検証器。
pub struct 有限全数の検証器 {
    遷移モデル: 遷移モデル,
    網羅性: 数え上げの網羅性, // 全称の成立と存在の不在を答えてよいかの判断がこれを読む
}

impl 有限全数の検証器 {
    /// 領域の探索の結末を受け取って組む。モデルと網羅性を別々に受けないのは、この2つが常に揃って
    /// 1つの探索から出るものであり、取り違えた組で検証器を作れないようにするためである。
    pub fn 生成する(探索の結末: 探索の結末) -> Self {
        Self {
            遷移モデル: 探索の結末.モデル,
            網羅性: 探索の結末.網羅性,
        }
    }

    /// 保持している遷移モデル。
    pub fn 遷移モデル(&self) -> &遷移モデル {
        &self.遷移モデル
    }

    /// 保持している数え上げの網羅性。
    pub fn 網羅性(&self) -> &数え上げの網羅性 {
        &self.網羅性
    }

    /// いま割り当てられている遷移。`遷移する`の原子は、存在の問いではなくこの遷移についての問いとして解く。
    /// 束縛の割り当てが当てた概念そのものを取り出す口を持たないため、再現の材料の表記で引き当てる。
    fn 割り当てられた遷移(&self, 割り当て: &束縛の割り当て) -> Option<&遷移> {
        割り当て
            .再現の材料へ写す()
            .into_iter()
            .find_map(|(_, 概念の表記)| self.遷移モデル.遷移一覧().iter().find(|候補| 候補.識別子().設計概念の識別子として表す().表記() == 概念の表記))
    }
}
