//! 有限全数の検証器とは、遷移モデルの状態と遷移を数え上げて振る舞いの命題を解く検証器のことである。
//!
//! **反例と存在の証人は「見た範囲」から得られるが、全称の成立と存在の不在は「見ていない範囲」に依る。**
//! この1文がこの検証器の振る舞いを決める。検証器は遷移モデルと数え上げの網羅性の両方を保持し、次の4つで答える。
//!
//! 1. 全称が全件で成立したとき、網羅性が `全件を数え上げた` なら証明済み、標本に限るか上限で打ち切ったなら
//!    `未決定の理由::探索の範囲では反例が無い` である。有限個の標本を「証明済み」と偽装しない
//! 2. 全称に反例が1件在るとき、網羅性に関わらず反証済みである。標本の中の反例は本物の反例である
//! 3. 存在に証人が1件在るとき、網羅性に関わらず証明済みである。標本の中の証人は本物の証人である
//! 4. 存在に証人が0件のとき、網羅性が `全件を数え上げた` なら反証済み、そうでなければ未決定である。
//!    見ていない値に証人が居るかもしれない
//!
//! `到達可能である` は存在の主張であるため、探索した集合にその状態が在れば網羅していなくても証明済みでよい。
//! 無ければ、網羅しているときだけ反証済みで答える。
//! この非対称は `検証結果` の3値が在る理由そのものである。真偽の2値だと4の未決定が偽へ潰れ、
//! 「見ていない範囲に証人が居ない」と断定することになる。
//!
//! 構造の原子命題(設計関係が在る・設計関係の経路が在る・マーカーを持つ・設計関係へ1つも参加していない)はこの検証器の対象ではないため、
//! 偽ではなく「この検証器が扱わない式を含む」で答える。偽で答えると、扱えない問いが成立しない問いと同じ結末になる。
//! 論理の結合の規則はこの木に書かず、`verifier` の結合を解く工程へ委譲する(規則を2箇所へ書き写さないため)。
//! 参照: `_doc/設計/設計オントロジー.md` 第9節。

