//! 生存台帳が固定する不変条件の試験。スロットの再利用で世代が変わること、古いIDが失効すること、
//! 反映前は問い合わせに現れないこと、世代が上限のスロットを再利用しないこと、順序が添字の昇順であることを見る。

use crate::liveness_error::生存台帳エラー;
use crate::liveness_ledger::生存台帳;
use crate::liveness_state::個体の生存状態;
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

#[test]
fn 破棄したスロットは世代を変えて再利用される() {
    let mut 台帳 = 生存台帳::生成する();
    let 最初の個体 = 台帳.実行時個体IDを発行する();
    assert_eq!(台帳.個体を反映済みにする(最初の個体), Ok(()));
    assert_eq!(台帳.個体を破棄する(最初の個体), Ok(()));
    let 次の個体 = 台帳.実行時個体IDを発行する();
    assert_eq!(台帳.スロットの総数(), 1);
    assert_ne!(最初の個体, 次の個体);
    assert_eq!(台帳.個体の生存状態を答える(最初の個体), 個体の生存状態::失効);
    assert_eq!(台帳.個体の生存状態を答える(次の個体), 個体の生存状態::反映待ち);
}

#[test]
fn 反映前の個体は反映待ちであり反映で生存になる() {
    let mut 台帳 = 生存台帳::生成する();
    let 個体 = 台帳.実行時個体IDを発行する();
    assert_eq!(台帳.個体の生存状態を答える(個体), 個体の生存状態::反映待ち);
    assert_eq!(台帳.生存している個体の数(), 0);
    assert_eq!(台帳.個体を反映済みにする(個体), Ok(()));
    assert_eq!(台帳.個体の生存状態を答える(個体), 個体の生存状態::生存);
    assert_eq!(台帳.生存している個体の数(), 1);
}

#[test]
fn 失効した個体への反映と破棄は型付きエラーで返る() {
    let mut 台帳 = 生存台帳::生成する();
    let 個体 = 台帳.実行時個体IDを発行する();
    assert_eq!(台帳.個体を破棄する(個体), Ok(()));
    assert_eq!(台帳.個体を破棄する(個体), Err(生存台帳エラー::失効した個体を破棄しようとした(個体)));
    assert_eq!(台帳.個体を反映済みにする(個体), Err(生存台帳エラー::失効した個体を反映済みにしようとした(個体)));
}

#[test]
fn 反映済みの個体をもう一度反映済みにすると型付きエラーで返る() {
    let mut 台帳 = 生存台帳::生成する();
    let 個体 = 台帳.実行時個体IDを発行する();
    assert_eq!(台帳.個体を反映済みにする(個体), Ok(()));
    assert_eq!(台帳.個体を反映済みにする(個体), Err(生存台帳エラー::既に反映済みの個体を反映済みにしようとした(個体)));
}

#[test]
fn 世代が上限のスロットは再利用されない() {
    let mut 台帳 = 生存台帳::世代を指定したスロットを1つ持つ台帳を生成する(u32::MAX);
    let 上限の個体 = ゲーム世界の実行時個体ID::生成する(0, u32::MAX);
    assert_eq!(台帳.個体を破棄する(上限の個体), Ok(()));
    let 次の個体 = 台帳.実行時個体IDを発行する();
    assert_eq!(台帳.スロットの総数(), 2);
    assert_eq!(次の個体, ゲーム世界の実行時個体ID::生成する(1, 0));
    assert_eq!(台帳.個体の生存状態を答える(上限の個体), 個体の生存状態::失効);
}

#[test]
#[allow(non_snake_case)] // 日本語の識別子に含むASCIIの大文字はRustの命名規則の検査に掛かる。ユビキタス言語の登録語をそのまま使う。
fn 実行時個体IDの順序は添字の昇順である() {
    let mut 台帳 = 生存台帳::生成する();
    let 先の個体 = 台帳.実行時個体IDを発行する();
    let 後の個体 = 台帳.実行時個体IDを発行する();
    assert!(先の個体 < 後の個体);
    let 世代が進んだ個体 = ゲーム世界の実行時個体ID::生成する(0, 9);
    assert!(世代が進んだ個体 < 後の個体);
}
