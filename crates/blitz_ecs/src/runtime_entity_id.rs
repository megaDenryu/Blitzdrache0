//! ゲーム世界の実行時個体ID: 生存台帳が発行する、スロットの添字と世代の組。
//! 世代を持つのは、破棄したスロットが再利用された後に、古いIDが新しい個体へ黙って当たる形を型で止めるためである。
//! 順序は(添字, 世代)の辞書式である。同じ添字に生きた個体が同時に2つ存在しないため、生きたIDの集合に対して
//! この順序は添字の昇順と一致し、走査の順序をIDの昇順で決めるという要求と整合する。
//!
//! 注意: 生成できるのは生存台帳だけである。添字と世代を読む口をクレートの中だけに閉じているのは、
//! 置き場が疎な配列を引くにはこの2つが要る一方で、外の層が生値から組み立て直す経路を作らせないためである。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断2」。

/// 実行中だけ有効な、世代を持つゲーム世界の個体の識別子。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct ゲーム世界の実行時個体ID {
    添字: u32,
    世代: u32,
}

impl ゲーム世界の実行時個体ID {
    pub(crate) fn 生成する(添字: u32, 世代: u32) -> Self {
        Self { 添字, 世代 }
    }

    pub(crate) fn スロットの添字(&self) -> u32 {
        self.添字
    }

    pub(crate) fn 世代(&self) -> u32 {
        self.世代
    }

    /// スロットの添字を、スロットごとの配列を引くための添字として読む。
    pub(crate) fn 配列の添字として読む(self) -> usize {
        let Ok(添字) = usize::try_from(self.添字) else {
            panic!("u32のスロットの添字がusizeへ収まらない(32ビット以上の環境だけを対象にする)")
        };
        添字
    }
}
