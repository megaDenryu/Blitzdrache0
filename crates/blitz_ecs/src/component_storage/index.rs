//! 疎な集合の索引: 疎な集合のうち、値を持たない側。スロットの添字から密な列の位置を引く疎な配列と、密な列の並びの
//! 実行時個体IDの列を持ち、密な列の並びが崩れているかを覚える。値の列は置き場が持ち、この索引が返す位置で同じ並びを保つ。
//!
//! 注意: 疎な配列は世代を持たないため、世代の一致は密な個体の列の要素と突き合わせて確かめる(契約21)。

use std::mem::size_of;

use super::dense_position::密な列の位置;
use super::permutation::添字の昇順の順列;
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

pub(super) struct 疎な集合の索引 {
    疎な配列: Vec<Option<密な列の位置>>, // スロットの添字で引く
    密な個体の列: Vec<ゲーム世界の実行時個体ID>,
    密な列の並びが崩れているか: bool,
}

impl 疎な集合の索引 {
    pub(super) fn 生成する() -> Self {
        Self {
            疎な配列: Vec::new(),
            密な個体の列: Vec::new(),
            密な列の並びが崩れているか: false,
        }
    }

    /// 世代まで一致する個体の、密な列の中の位置。世代が違うIDには不在を返す。
    pub(super) fn 密な列の位置を参照する(&self, 個体: ゲーム世界の実行時個体ID) -> Option<usize> {
        let 位置 = (*self.疎な配列.get(個体.配列の添字として読む())?)?.列の添字として読む();
        (self.密な個体の列[位置] == 個体).then_some(位置)
    }

    /// 個体を密な列の末尾へ足し、その位置を返す。既に持っていれば不在を返し、何も変えない。
    pub(super) fn 追加する(&mut self, 個体: ゲーム世界の実行時個体ID) -> Option<usize> {
        let 枠 = 個体.配列の添字として読む();
        if 枠 >= self.疎な配列.len() {
            self.疎な配列.resize(枠 + 1, None);
        }
        if let Some(位置) = self.疎な配列[枠] {
            if self.密な個体の列[位置.列の添字として読む()] == 個体 {
                return None;
            }
            panic!("スロット{枠}に別の世代の個体の値が残っている(個体が消えるときに全個体構成要素を取り除く規律が破られた)")
        }
        if self.密な個体の列.last().is_some_and(|末尾の個体| 個体 < *末尾の個体) {
            self.密な列の並びが崩れているか = true;
        }
        let 位置 = self.密な個体の列.len();
        self.疎な配列[枠] = Some(密な列の位置::生成する(位置));
        self.密な個体の列.push(個体);
        Some(位置)
    }

    /// 個体を密な列から取り除き、値の列が同じ入れ替え(末尾との交換)をするための位置を返す。末尾を動かしたなら並びが崩れたことを覚える。
    pub(super) fn 取り除く(&mut self, 個体: ゲーム世界の実行時個体ID) -> Option<usize> {
        let 位置 = self.密な列の位置を参照する(個体)?;
        let 末尾を動かしたか = 位置 != self.密な個体の列.len() - 1;
        self.密な個体の列.swap_remove(位置);
        self.疎な配列[個体.配列の添字として読む()] = None;
        if 末尾を動かしたか {
            let 動かした個体 = self.密な個体の列[位置];
            self.疎な配列[動かした個体.配列の添字として読む()] = Some(密な列の位置::生成する(位置));
            self.密な列の並びが崩れているか = true;
        }
        Some(位置)
    }

    /// 並びが崩れていれば実行時個体IDの昇順へ戻し、値の列へ当てるべき同じ順列を返す。崩れていなければ不在を返す。
    pub(super) fn 添字の昇順へ並べ直す(&mut self) -> Option<添字の昇順の順列> {
        if !self.密な列の並びが崩れているか {
            return None;
        }
        let 順列 = 添字の昇順の順列::個体の列から作る(&self.密な個体の列);
        順列.適用する(&mut self.密な個体の列);
        for (位置, 個体) in self.密な個体の列.iter().enumerate() {
            self.疎な配列[個体.配列の添字として読む()] = Some(密な列の位置::生成する(位置));
        }
        self.密な列の並びが崩れているか = false;
        Some(順列)
    }

    /// 走査の前に呼ぶ。並びが崩れたまま走査するのはバグであり panic で止める。型の名前は panic の文に書くために受ける。
    pub(super) fn 並びが崩れていないことを確かめる(&self, 型の名前: &'static str) {
        if self.密な列の並びが崩れているか {
            panic!("密な列の並びが崩れたまま型{型の名前}の置き場を走査した(構造変更の反映の境界が並べ直してから走査する)")
        }
    }

    pub(super) fn 密な個体の列(&self) -> &[ゲーム世界の実行時個体ID] {
        &self.密な個体の列
    }

    pub(super) fn 占有量のバイト数(&self) -> usize {
        self.疎な配列.capacity() * size_of::<Option<密な列の位置>>() + self.密な個体の列.capacity() * size_of::<ゲーム世界の実行時個体ID>()
    }
}
