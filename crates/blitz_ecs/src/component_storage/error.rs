//! 個体構成要素の置き場が拒む要求。同じ個体へ同じ型の2つ目を置く要求だけが選択肢である(契約11)。
//! 2つ以上が要るなら、その複数を持つ1つの型を作る。

use thiserror::Error;

use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

/// 個体構成要素の置き場への追加が拒む要求。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 個体構成要素の置き場エラー {
    /// その個体が既にこの型を持っている。
    #[error("個体{個体:?}は既に型{型の名前}を持っている(同じ型の2つ目は置けない)")]
    既に同じ型を持っている {
        /// 拒んだ相手の個体。
        個体: ゲーム世界の実行時個体ID,
        /// 置こうとした型の、人が読む名前。
        型の名前: &'static str,
    },
}
