//! 添字の昇順の順列: 密な列を実行時個体IDの昇順へ並べ直すための、位置ごとの移動元の一覧。
//! IDの列と値の列を同じ並びで持つ密な列は、IDの列から順列を1つ作り、その順列を両方の列へ同じ手順で当てる。
//! 当てる手順は巡回を辿る入れ替えであり、値を複製せず、列の長さぶんの真偽の一覧だけを確保する。

use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

pub(crate) struct 添字の昇順の順列 {
    位置ごとの移動元: Vec<usize>, // 並べ直した後の位置kに来る要素が、並べ直す前にどこにあったか
}

impl 添字の昇順の順列 {
    pub(crate) fn 個体の列から作る(個体の列: &[ゲーム世界の実行時個体ID]) -> Self {
        let mut 位置ごとの移動元: Vec<usize> = (0..個体の列.len()).collect();
        位置ごとの移動元.sort_unstable_by_key(|移動元| 個体の列[*移動元]);
        Self { 位置ごとの移動元 }
    }

    /// 列を、この順列が定める並びへ入れ替える。同じ順列をIDの列と値の列の両方へ当てる。
    pub(crate) fn 適用する<T>(&self, 列: &mut [T]) {
        if 列.len() != self.位置ごとの移動元.len() {
            panic!("順列の長さ{}と列の長さ{}が違う(IDの列と値の列は同じ長さを保つ)", self.位置ごとの移動元.len(), 列.len())
        }
        let mut 配置済み = vec![false; 列.len()];
        for 起点 in 0..列.len() {
            if 配置済み[起点] {
                continue;
            }
            let mut 現在 = 起点;
            loop {
                配置済み[現在] = true;
                let 移動元 = self.位置ごとの移動元[現在];
                if 移動元 == 起点 {
                    break;
                }
                列.swap(現在, 移動元);
                現在 = 移動元;
            }
        }
    }
}
