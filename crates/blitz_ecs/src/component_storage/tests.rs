//! 個体構成要素の置き場が固定する不変条件の試験。追加・参照・取り除き・2つ目の追加の拒否・
//! 並べ直しの後の走査がIDの昇順であること・世代の違うIDが不在になることを見る。

use super::個体構成要素の置き場;
use super::個体構成要素の置き場エラー;
use crate::liveness_ledger::生存台帳;
use crate::naive_baseline_samples::見本の位置;
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

fn 個体を用意する(個体数: usize) -> (生存台帳, Vec<ゲーム世界の実行時個体ID>) {
    let mut 台帳 = 生存台帳::生成する();
    let 個体一覧 = (0..個体数).map(|_| 台帳.実行時個体IDを発行する()).collect();
    (台帳, 個体一覧)
}

#[test]
fn 追加と参照と取り除きが対応する() {
    let (_台帳, 個体一覧) = 個体を用意する(3);
    let mut 置き場 = 個体構成要素の置き場::生成する();
    assert_eq!(置き場.追加する(個体一覧[1], 見本の位置::生成する([1.0, 2.0, 3.0])), Ok(()));
    assert_eq!(置き場.参照する(個体一覧[1]), Some(&見本の位置::生成する([1.0, 2.0, 3.0])));
    assert_eq!(置き場.参照する(個体一覧[0]), None);
    assert!(置き場.参照する(個体一覧[1]).is_some());
    assert_eq!(置き場.件数(), 1);
    assert_eq!(置き場.取り除く(個体一覧[1]), Some(見本の位置::生成する([1.0, 2.0, 3.0])));
    assert_eq!(置き場.取り除く(個体一覧[1]), None);
    assert_eq!(置き場.件数(), 0);
}

#[test]
fn 同じ個体への2つ目の追加は型付きエラーで返る() {
    let (_台帳, 個体一覧) = 個体を用意する(1);
    let mut 置き場 = 個体構成要素の置き場::生成する();
    assert_eq!(置き場.追加する(個体一覧[0], 見本の位置::生成する([1.0, 1.0, 1.0])), Ok(()));
    let 結果 = 置き場.追加する(個体一覧[0], 見本の位置::生成する([2.0, 2.0, 2.0]));
    assert!(matches!(結果, Err(個体構成要素の置き場エラー::既に同じ型を持っている { 個体, .. }) if 個体 == 個体一覧[0]));
    assert_eq!(置き場.参照する(個体一覧[0]), Some(&見本の位置::生成する([1.0, 1.0, 1.0])));
}

#[test]
fn 世代の違う古い個体の値は不在になる() {
    let mut 台帳 = 生存台帳::生成する();
    let 古い個体 = 台帳.実行時個体IDを発行する();
    let mut 置き場 = 個体構成要素の置き場::生成する();
    assert_eq!(置き場.追加する(古い個体, 見本の位置::生成する([1.0, 1.0, 1.0])), Ok(()));
    assert_eq!(置き場.取り除く(古い個体), Some(見本の位置::生成する([1.0, 1.0, 1.0])));
    assert_eq!(台帳.個体を破棄する(古い個体), Ok(()));
    let 新しい個体 = 台帳.実行時個体IDを発行する();
    assert_eq!(置き場.追加する(新しい個体, 見本の位置::生成する([2.0, 2.0, 2.0])), Ok(()));
    assert_eq!(置き場.参照する(古い個体), None);
    assert!(置き場.参照する(古い個体).is_none());
}

#[test]
#[allow(non_snake_case)] // 日本語の識別子に含むASCIIの大文字はRustの命名規則の検査に掛かる。ユビキタス言語の登録語をそのまま使う。
fn 並べ直しの後の走査は実行時個体IDの昇順である() {
    let (_台帳, 個体一覧) = 個体を用意する(5);
    let mut 置き場 = 個体構成要素の置き場::生成する();
    for (番号, 値) in [(4_usize, 4.0), (0, 0.0), (3, 3.0), (1, 1.0), (2, 2.0)] {
        assert_eq!(置き場.追加する(個体一覧[番号], 見本の位置::生成する([値, 0.0, 0.0])), Ok(()));
    }
    assert_eq!(置き場.取り除く(個体一覧[3]), Some(見本の位置::生成する([3.0, 0.0, 0.0])));
    置き場.密な列を添字の昇順へ並べ直す();
    let 走査した個体一覧: Vec<_> = 置き場.IDの昇順で走査する().map(|(個体, 位置)| (個体, 位置.成分の和())).collect();
    assert_eq!(走査した個体一覧, vec![(個体一覧[0], 0.0), (個体一覧[1], 1.0), (個体一覧[2], 2.0), (個体一覧[4], 4.0)]);
    for 個体 in [個体一覧[0], 個体一覧[1], 個体一覧[2], 個体一覧[4]] {
        assert_eq!(置き場.参照する(個体).map(見本の位置::成分の和), Some(f64::from(個体.スロットの添字())));
    }
}

#[test]
#[should_panic(expected = "並びが崩れたまま")]
fn 並びが崩れたままの走査は止まる() {
    let (_台帳, 個体一覧) = 個体を用意する(2);
    let mut 置き場 = 個体構成要素の置き場::生成する();
    assert_eq!(置き場.追加する(個体一覧[1], 見本の位置::生成する([0.0; 3])), Ok(()));
    assert_eq!(置き場.追加する(個体一覧[0], 見本の位置::生成する([0.0; 3])), Ok(()));
    let _ = 置き場.IDの昇順で走査する().count();
}
