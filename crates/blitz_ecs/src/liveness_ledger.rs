//! 生存台帳: 実行時個体IDを発行し、その個体が生存・反映待ち・失効のどれであるかをO(1)で答える台帳。
//! 実行時個体IDを作れるのはこの型だけであり、添字と世代の組を外から組み立て直す経路を持たない。
//!
//! 注意: 破棄したスロットは世代を1つ進めてから空き列へ戻す。進められなかったスロット(世代が上限)は
//! 戻さないため、古いIDが新しい個体へ当たることがない。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断2」。

use crate::liveness_error::生存台帳エラー;
use crate::liveness_slot::{スロットの再利用の可否, 生存台帳のスロット};
use crate::liveness_state::個体の生存状態;
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

/// 実行時個体IDの発行と、その個体の生存状態の判定を担う台帳。
pub struct 生存台帳 {
    スロット一覧: Vec<生存台帳のスロット>,
    空きスロットの添字一覧: Vec<u32>,
    生存している個体の数: usize,
}

impl 生存台帳 {
    /// 個体を1つも持たない台帳を作る。
    pub fn 生成する() -> Self {
        Self {
            スロット一覧: Vec::new(),
            空きスロットの添字一覧: Vec::new(),
            生存している個体の数: 0,
        }
    }

    /// 新しい個体のIDを発行する。発行した個体は、反映の境界を通るまで反映待ちであり問い合わせに現れない。
    // 日本語の識別子に含むASCIIの大文字は、Rustの命名規則の検査に掛かる。ユビキタス言語の登録語をそのまま使うため、ここだけ外す。
    #[allow(non_snake_case)]
    pub fn 実行時個体IDを発行する(&mut self) -> ゲーム世界の実行時個体ID {
        let Some(添字) = self.空きスロットの添字一覧.pop() else {
            return self.スロットを1つ増やして発行する();
        };
        let Some(スロット) = self.スロットを可変に引く(添字) else {
            panic!("空き列の添字{添字}がスロット一覧に無い(空き列は破棄したスロットの添字だけを持つ)")
        };
        スロット.反映待ちで再利用する();
        ゲーム世界の実行時個体ID::生成する(添字, スロット.世代())
    }

    /// 反映待ちの個体を生存へ移す。失効した個体と、既に反映済みの個体は拒む。
    pub fn 個体を反映済みにする(&mut self, 個体: ゲーム世界の実行時個体ID) -> Result<(), 生存台帳エラー> {
        let Some(スロット) = self.世代が一致するスロットを可変に引く(個体) else {
            return Err(生存台帳エラー::失効した個体を反映済みにしようとした(個体));
        };
        match スロット.生存状態() {
            個体の生存状態::反映待ち => スロット.反映済みにする(),
            個体の生存状態::生存 => return Err(生存台帳エラー::既に反映済みの個体を反映済みにしようとした(個体)),
            個体の生存状態::失効 => return Err(生存台帳エラー::失効した個体を反映済みにしようとした(個体)),
        }
        self.生存している個体の数 += 1;
        Ok(())
    }

    /// 生存または反映待ちの個体を失効させ、スロットの世代を進めて空き列へ戻す。失効した個体は拒む。
    pub fn 個体を破棄する(&mut self, 個体: ゲーム世界の実行時個体ID) -> Result<(), 生存台帳エラー> {
        let Some(スロット) = self.世代が一致するスロットを可変に引く(個体) else {
            return Err(生存台帳エラー::失効した個体を破棄しようとした(個体));
        };
        let 反映済みだったか = match スロット.生存状態() {
            個体の生存状態::生存 => true,
            個体の生存状態::反映待ち => false,
            個体の生存状態::失効 => return Err(生存台帳エラー::失効した個体を破棄しようとした(個体)),
        };
        let 再利用の可否 = スロット.失効させて世代を進める();
        match 再利用の可否 {
            スロットの再利用の可否::再利用してよい => self.空きスロットの添字一覧.push(個体.スロットの添字()),
            スロットの再利用の可否::世代が上限に達した => {}
        }
        if 反映済みだったか {
            self.生存している個体の数 -= 1;
        }
        Ok(())
    }

    /// 実行時個体IDが指す個体の生存状態を答える。世代が一致しないIDには失効を返す。
    pub fn 個体の生存状態を答える(&self, 個体: ゲーム世界の実行時個体ID) -> 個体の生存状態 {
        match self.スロットを引く(個体.スロットの添字()) {
            Some(スロット) if スロット.世代() == 個体.世代() => スロット.生存状態(),
            _ => 個体の生存状態::失効,
        }
    }

    /// 反映済みで生存している個体の数。反映待ちの個体は数えない。
    pub fn 生存している個体の数(&self) -> usize {
        self.生存している個体の数
    }

    /// これまでに確保したスロットの総数。破棄して空き列へ戻したスロットも数える。
    pub fn スロットの総数(&self) -> usize {
        self.スロット一覧.len()
    }

    #[cfg(test)]
    pub(crate) fn 世代を指定したスロットを1つ持つ台帳を生成する(世代: u32) -> Self {
        Self {
            スロット一覧: vec![生存台帳のスロット::世代を指定して反映待ちで生成する(世代)],
            空きスロットの添字一覧: Vec::new(),
            生存している個体の数: 0,
        }
    }

    fn スロットを1つ増やして発行する(&mut self) -> ゲーム世界の実行時個体ID {
        let Ok(添字) = u32::try_from(self.スロット一覧.len()) else {
            panic!("スロットの総数がu32の範囲を超えた(実行時個体IDの添字はu32で持つ)")
        };
        let スロット = 生存台帳のスロット::反映待ちで生成する();
        let 世代 = スロット.世代();
        self.スロット一覧.push(スロット);
        ゲーム世界の実行時個体ID::生成する(添字, 世代)
    }

    fn スロットを引く(&self, 添字: u32) -> Option<&生存台帳のスロット> {
        usize::try_from(添字).ok().and_then(|位置| self.スロット一覧.get(位置))
    }

    fn スロットを可変に引く(&mut self, 添字: u32) -> Option<&mut 生存台帳のスロット> {
        usize::try_from(添字).ok().and_then(|位置| self.スロット一覧.get_mut(位置))
    }

    fn 世代が一致するスロットを可変に引く(&mut self, 個体: ゲーム世界の実行時個体ID) -> Option<&mut 生存台帳のスロット> {
        self.スロットを可変に引く(個体.スロットの添字()).filter(|スロット| スロット.世代() == 個体.世代())
    }
}
