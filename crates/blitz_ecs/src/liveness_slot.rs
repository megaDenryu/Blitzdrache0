//! 生存台帳のスロット1つ分の世代と生存状態。台帳から分けているのは、世代を進めてよいかの判断が
//! このスロット1つの中だけで完結し、台帳の空き列も生存の件数も見ないためである。
//!
//! 注意: 世代がu32で一周すると、古いIDが新しい個体へ一致して黙って誤接続する。上限に達したスロットは
//! 世代を進められないため、台帳は二度と再利用しない。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断2」。

use crate::liveness_state::個体の生存状態;

/// 失効させたスロットを空き列へ戻してよいかの判定。
pub(crate) enum スロットの再利用の可否 {
    再利用してよい,
    世代が上限に達した,
}

pub(crate) struct 生存台帳のスロット {
    世代: u32,
    生存状態: 個体の生存状態,
}

impl 生存台帳のスロット {
    pub(crate) fn 反映待ちで生成する() -> Self {
        Self {
            世代: 0, 生存状態: 個体の生存状態::反映待ち
        }
    }

    #[cfg(test)]
    pub(crate) fn 世代を指定して反映待ちで生成する(世代: u32) -> Self {
        Self {
            世代, 生存状態: 個体の生存状態::反映待ち
        }
    }

    pub(crate) fn 世代(&self) -> u32 {
        self.世代
    }

    pub(crate) fn 生存状態(&self) -> 個体の生存状態 {
        self.生存状態
    }

    pub(crate) fn 反映待ちで再利用する(&mut self) {
        self.生存状態 = 個体の生存状態::反映待ち;
    }

    pub(crate) fn 反映済みにする(&mut self) {
        self.生存状態 = 個体の生存状態::生存;
    }

    pub(crate) fn 失効させて世代を進める(&mut self) -> スロットの再利用の可否 {
        self.生存状態 = 個体の生存状態::失効;
        match self.世代.checked_add(1) {
            Some(次の世代) => {
                self.世代 = 次の世代;
                スロットの再利用の可否::再利用してよい
            }
            None => スロットの再利用の可否::世代が上限に達した,
        }
    }
}
