//! 素朴な置き場の計測。測る4つの項目を名前のある列挙で表し、項目ごとに3回走らせて中央値を採る。
//! 項目を列挙にしているのは、走らせる相手が「行われる操作」であり、無名の関数では名前を持てないためである。
//!
//! この計測は疎な集合(判断3)を書いた後に同じ4項目を並べるための比較対象であり、本番の経路には現れない。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断8」。

mod report_row;
mod tests;
mod workload;

use std::time::Duration;

use report_row::計測の結果の行;

/// 素朴な置き場について測る4つの項目。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 計測の項目 {
    生成と破棄,
    一つの型の走査,
    二つの型の問い合わせ,
    個体構成要素の追加と削除,
}

impl 計測の項目 {
    pub(crate) const 全項目: [計測の項目; 4] = [計測の項目::生成と破棄, 計測の項目::一つの型の走査, 計測の項目::二つの型の問い合わせ, 計測の項目::個体構成要素の追加と削除];

    /// 3回走らせ、所要時間の中央値を1行の記録にして返す。3回にするのは、最初の1回に入る確保の揺れを外すためである。
    pub(crate) fn 三回走らせて中央値を採る(self, 個体数: u32) -> 計測の結果の行 {
        let mut 所要時間一覧 = [self.一度走らせる(個体数), self.一度走らせる(個体数), self.一度走らせる(個体数)];
        所要時間一覧.sort_unstable();
        計測の結果の行::生成する(self.名前(), 個体数, 所要時間一覧[1])
    }

    fn 名前(self) -> &'static str {
        match self {
            計測の項目::生成と破棄 => "生成と破棄",
            計測の項目::一つの型の走査 => "1型の走査",
            計測の項目::二つの型の問い合わせ => "2型の問い合わせ",
            計測の項目::個体構成要素の追加と削除 => "追加と削除",
        }
    }

    fn 一度走らせる(self, 個体数: u32) -> Duration {
        match self {
            計測の項目::生成と破棄 => workload::生成と破棄の所要時間を測る(個体数),
            計測の項目::一つの型の走査 => workload::一つの型の走査の所要時間を測る(個体数),
            計測の項目::二つの型の問い合わせ => workload::二つの型の問い合わせの所要時間を測る(個体数),
            計測の項目::個体構成要素の追加と削除 => workload::追加と削除の所要時間を測る(個体数),
        }
    }
}
