//! 計測の項目が1回ずつ走らせる4つの仕事と、その下ごしらえ。どれも計測の外で台帳と置き場を用意し、
//! 測る区間だけを`Instant`で囲む。このモジュールの関数は計測の項目の列挙だけが呼ぶ工程であり、
//! 依存を持たず自分で状態を組み立てるため、外へ運ぶものが無い。
//!
//! 注意: 走査の結果は`black_box`へ渡す。渡さないと最適化が走査ごと消し、0に近い数字が出る。
//! 生成と破棄の計測だけは、台帳が返す結果を数えることが`black_box`の代わりになる。数えた回数は計測の外で突き合わせる。

use std::hint::black_box;
use std::time::{Duration, Instant};

use crate::liveness_ledger::生存台帳;
use crate::naive_baseline::素朴な個体構成要素の置き場;
use crate::naive_baseline_samples::{見本の位置, 見本の小さな状態};
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

pub(super) fn 生成と破棄の所要時間を測る(個体数: u32) -> Duration {
    let mut 台帳 = 生存台帳::生成する();
    let mut 反映と破棄が通った回数 = 0_u32;
    let 開始 = Instant::now();
    for _ in 0..個体数 {
        let 個体 = 台帳.実行時個体IDを発行する();
        if 台帳.個体を反映済みにする(個体).is_ok() && 台帳.個体を破棄する(個体).is_ok() {
            反映と破棄が通った回数 += 1;
        }
    }
    let 所要時間 = 開始.elapsed();
    assert_eq!(反映と破棄が通った回数, 個体数, "生成と破棄の計測で台帳が要求を拒んだ");
    所要時間
}

pub(super) fn 一つの型の走査の所要時間を測る(個体数: u32) -> Duration {
    let (_台帳, 個体一覧) = 生存する個体を用意する(個体数);
    let 位置の置き場 = 位置の置き場を埋める(&個体一覧);
    let 開始 = Instant::now();
    let mut 合計 = 0.0_f64;
    for (_, 位置) in 位置の置き場.走査する() {
        合計 += 位置.成分の和();
    }
    let 所要時間 = 開始.elapsed();
    black_box(合計);
    所要時間
}

pub(super) fn 二つの型の問い合わせの所要時間を測る(個体数: u32) -> Duration {
    let (_台帳, 個体一覧) = 生存する個体を用意する(個体数);
    let 位置の置き場 = 位置の置き場を埋める(&個体一覧);
    let 状態の置き場 = 小さな状態の置き場を1つ飛ばしで埋める(&個体一覧);
    let 開始 = Instant::now();
    let mut 合計 = 0.0_f64;
    for (_, 位置, 状態) in 位置の置き場.自分と相手の両方を持つ個体を走査する(&状態の置き場) {
        合計 += 位置.成分の和() + f64::from(状態.残り体力());
    }
    let 所要時間 = 開始.elapsed();
    black_box(合計);
    所要時間
}

pub(super) fn 追加と削除の所要時間を測る(個体数: u32) -> Duration {
    let (_台帳, 個体一覧) = 生存する個体を用意する(個体数);
    let mut 位置の置き場 = 素朴な個体構成要素の置き場::生成する();
    let 開始 = Instant::now();
    for 個体 in &個体一覧 {
        black_box(位置の置き場.追加する(*個体, 見本の位置::生成する([1.0, 2.0, 3.0])));
    }
    for 個体 in &個体一覧 {
        black_box(位置の置き場.削除する(*個体));
    }
    開始.elapsed()
}

fn 生存する個体を用意する(個体数: u32) -> (生存台帳, Vec<ゲーム世界の実行時個体ID>) {
    let mut 台帳 = 生存台帳::生成する();
    let mut 個体一覧 = Vec::new();
    for _ in 0..個体数 {
        let 個体 = 台帳.実行時個体IDを発行する();
        assert!(台帳.個体を反映済みにする(個体).is_ok(), "用意した個体の反映を台帳が拒んだ");
        個体一覧.push(個体);
    }
    (台帳, 個体一覧)
}

fn 位置の置き場を埋める(個体一覧: &[ゲーム世界の実行時個体ID]) -> 素朴な個体構成要素の置き場<見本の位置> {
    let mut 置き場 = 素朴な個体構成要素の置き場::生成する();
    for (順番, 個体) in 個体一覧.iter().enumerate() {
        let Ok(番号) = u32::try_from(順番 % 1000) else {
            panic!("1000未満の値がu32へ収まらない(剰余の上限を変えたなら型も直す)")
        };
        let 値 = f64::from(番号);
        black_box(置き場.追加する(*個体, 見本の位置::生成する([値, 値 + 1.0, 値 + 2.0])));
    }
    置き場
}

fn 小さな状態の置き場を1つ飛ばしで埋める(個体一覧: &[ゲーム世界の実行時個体ID]) -> 素朴な個体構成要素の置き場<見本の小さな状態> {
    let mut 置き場 = 素朴な個体構成要素の置き場::生成する();
    for 個体 in 個体一覧.iter().step_by(2) {
        black_box(置き場.追加する(*個体, 見本の小さな状態::生成する(100, true)));
    }
    置き場
}
