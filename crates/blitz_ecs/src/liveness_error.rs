//! 生存台帳が拒む要求。失効した個体への反映と破棄、および反映済みの個体を再び反映済みにする要求が選択肢である。
//! どれも呼び出し側の取り違えであり、黙って無視すると台帳が数える生存の件数と実体がずれるため、型付きエラーで返す。
//!
//! 拒んだ相手を添字と世代の2つの数でなく実行時個体IDのまま運ぶのは、受け取った側がその2つを組み直す必要を無くすためである。

use thiserror::Error;

use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

/// 生存台帳の操作が拒む要求。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 生存台帳エラー {
    /// 失効した個体を反映済みにしようとした。
    #[error("失効した個体{0:?}を反映済みにしようとした")]
    失効した個体を反映済みにしようとした(ゲーム世界の実行時個体ID),
    /// 反映済みの個体を、もう一度反映済みにしようとした。
    #[error("既に反映済みの個体{0:?}をもう一度反映済みにしようとした")]
    既に反映済みの個体を反映済みにしようとした(ゲーム世界の実行時個体ID),
    /// 失効した個体を破棄しようとした。
    #[error("失効した個体{0:?}を破棄しようとした")]
    失効した個体を破棄しようとした(ゲーム世界の実行時個体ID),
}
