//! 個体の生存状態: 生存台帳が実行時個体IDに対して答える3つの状態。
//! 反映待ちを生存とも失効とも別の枝で持つのは、「生きているのに問い合わせに現れない」を真偽の1語で
//! 通す形を禁じるためである。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断2」。

/// 実行時個体IDが指す個体が、生存台帳から見ていまどの状態にあるか。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum 個体の生存状態 {
    /// 反映済みであり、個体群への問い合わせに現れる。
    生存,
    /// IDは発行済みだが、まだ反映の境界を通っていないため問い合わせに現れない。
    反映待ち,
    /// 破棄済みであるか、スロットの世代がIDの世代と一致しない。
    失効,
}
