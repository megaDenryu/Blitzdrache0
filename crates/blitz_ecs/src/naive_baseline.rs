//! 計測専用の素朴な個体構成要素の置き場。実行時個体IDを鍵にした `HashMap` を型ごとに1つ持つ形であり、
//! 疎な集合(判断3)の数字と並べる比較対象としてだけ存在する。本番の置き場の候補ではないため、
//! このモジュールは `#[cfg(test)]` の下にだけ置く。
//!
//! 標識となる`trait`(判断4)はまだ無いため、型引数に境界を課さない。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断8」。

use std::collections::HashMap;

use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

/// 素朴な置き場への追加が、値を入れたかどうか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 素朴な置き場への追加の結果 {
    追加した,
    既に持っていたため追加しなかった,
}

/// 実行時個体IDから型Tの値を引く、計測の比較対象としての置き場。
pub(crate) struct 素朴な個体構成要素の置き場<T> {
    値の表: HashMap<ゲーム世界の実行時個体ID, T>,
}

impl<T> 素朴な個体構成要素の置き場<T> {
    pub(crate) fn 生成する() -> Self {
        Self { 値の表: HashMap::new() }
    }

    /// 個体へ値を追加する。その個体が既にこの型を持っていたなら追加せず、渡された値を捨てる。
    /// 捨てた値を返す口を持たないのは、この置き場が計測専用であり復帰の経路を要さないためである。
    pub(crate) fn 追加する(&mut self, 個体: ゲーム世界の実行時個体ID, 値: T) -> 素朴な置き場への追加の結果 {
        if self.値の表.contains_key(&個体) {
            return 素朴な置き場への追加の結果::既に持っていたため追加しなかった;
        }
        self.値の表.insert(個体, 値);
        素朴な置き場への追加の結果::追加した
    }

    pub(crate) fn 取得する(&self, 個体: ゲーム世界の実行時個体ID) -> Option<&T> {
        self.値の表.get(&個体)
    }

    pub(crate) fn 削除する(&mut self, 個体: ゲーム世界の実行時個体ID) -> Option<T> {
        self.値の表.remove(&個体)
    }

    pub(crate) fn 件数(&self) -> usize {
        self.値の表.len()
    }

    /// この置き場が持つ全個体を走査する。並びは`HashMap`の並びであり、実行時個体IDの昇順ではない。
    /// 注意: 契約25(走査の順序がIDの昇順で決まる)をこの置き場は満たさない。比較対象としての素朴さの一部である。
    pub(crate) fn 走査する(&self) -> impl Iterator<Item = (ゲーム世界の実行時個体ID, &T)> {
        self.値の表.iter().map(|(個体, 値)| (*個体, 値))
    }

    /// 自分と相手の両方が値を持つ個体だけを走査する。自分を走査して相手の表を1件ずつ引く形である。
    pub(crate) fn 自分と相手の両方を持つ個体を走査する<'a, U>(&'a self, 相手: &'a 素朴な個体構成要素の置き場<U>) -> impl Iterator<Item = (ゲーム世界の実行時個体ID, &'a T, &'a U)> {
        self.走査する().filter_map(|(個体, 値)| 相手.取得する(個体).map(|相手の値| (個体, 値, 相手の値)))
    }
}
