//! 素朴な置き場が正しく動くことを固定する試験。計測の試験は`#[ignore]`で普段は走らないため、
//! 壊れた実装を測ってしまう形を防ぐために、この1本だけは普段の検証で走らせる。

use crate::liveness_ledger::生存台帳;
use crate::naive_baseline::{素朴な個体構成要素の置き場, 素朴な置き場への追加の結果};
use crate::naive_baseline_samples::{見本の位置, 見本の小さな状態};

#[test]
fn 素朴な置き場の追加と取得と削除と二つの型の走査が正しい() {
    let mut 台帳 = 生存台帳::生成する();
    let 甲 = 台帳.実行時個体IDを発行する();
    let 乙 = 台帳.実行時個体IDを発行する();

    let mut 位置の置き場 = 素朴な個体構成要素の置き場::生成する();
    assert_eq!(位置の置き場.追加する(甲, 見本の位置::生成する([1.0, 2.0, 3.0])), 素朴な置き場への追加の結果::追加した);
    assert_eq!(位置の置き場.追加する(乙, 見本の位置::生成する([4.0, 5.0, 6.0])), 素朴な置き場への追加の結果::追加した);
    assert_eq!(位置の置き場.追加する(甲, 見本の位置::生成する([9.0, 9.0, 9.0])), 素朴な置き場への追加の結果::既に持っていたため追加しなかった);
    assert_eq!(位置の置き場.取得する(甲), Some(&見本の位置::生成する([1.0, 2.0, 3.0])));
    assert_eq!(位置の置き場.件数(), 2);

    let mut 状態の置き場 = 素朴な個体構成要素の置き場::生成する();
    assert_eq!(状態の置き場.追加する(乙, 見本の小さな状態::生成する(7, true)), 素朴な置き場への追加の結果::追加した);
    let 両方を持つ個体一覧: Vec<_> = 位置の置き場
        .自分と相手の両方を持つ個体を走査する(&状態の置き場)
        .map(|(個体, 位置, 状態)| (個体, 位置.成分の和(), 状態.残り体力(), 状態.地面に接しているか()))
        .collect();
    assert_eq!(両方を持つ個体一覧, vec![(乙, 15.0, 7, true)]);

    assert_eq!(位置の置き場.削除する(甲), Some(見本の位置::生成する([1.0, 2.0, 3.0])));
    assert_eq!(位置の置き場.取得する(甲), None);
    assert_eq!(位置の置き場.件数(), 1);
    assert_eq!(位置の置き場.走査する().count(), 1);
}
