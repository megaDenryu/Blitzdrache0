//! 読みながら構造変更を予約する借り: 個体群の生存台帳の発行口と、置き場の集まりへの共有の参照を、分割借用で同時に持つ借り。
//! 遅延構造変更の代表的な使い方(走査しながら、その個体について生成と追加を予約する。ゲーム実行基盤の構造変更の節が定める形)は、
//! 読む借りを保持したまま `&mut ゲーム世界の個体群` を要る生成の予約を呼べないため、この借りが両方を1つの口から貸す。
//!
//! 読む借りは `&self` でなく持っている参照の寿命 `'a` で返す。`&self` の寿命で返すと、読む借りを保持したまま生成を予約する
//! (`&mut self`)ことができず、この型を置く理由が消える。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断7」。

use super::id_issuer::実行時個体IDの発行口;
use super::structural_change::{構造変更の予約, 構造変更の予約エラー};
use crate::borrow::{一型を読む借り, 二型を読む借り};
use crate::component_marker::個体構成要素;
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;
use crate::storage_collection::個体構成要素の置き場の集まり;

/// 置き場を読みながら、同じ個体群への構造変更を予約するための借り。
pub struct 読みながら構造変更を予約する借り<'a> {
    発行口: 実行時個体IDの発行口<'a>,
    置き場の集まり: &'a 個体構成要素の置き場の集まり,
}

impl<'a> 読みながら構造変更を予約する借り<'a> {
    pub(super) fn 生成する(発行口: 実行時個体IDの発行口<'a>, 置き場の集まり: &'a 個体構成要素の置き場の集まり) -> Self {
        Self { 発行口, 置き場の集まり }
    }

    /// 新しい個体の生成を予約へ積み、発行した実行時個体IDを返す。個体は反映まで反映待ちであり問い合わせに現れない。
    pub fn 個体の生成を予約する(&mut self, 予約: &mut 構造変更の予約) -> ゲーム世界の実行時個体ID {
        self.発行口.個体の生成を予約する(予約)
    }

    /// 個体への型Tの追加を予約へ積む。置き場が既に持っているか、その列に既に積んであれば拒む(契約11)。
    pub fn 追加を予約する<T: 個体構成要素>(&self, 予約: &mut 構造変更の予約, 個体: ゲーム世界の実行時個体ID, 値: T) -> Result<(), 構造変更の予約エラー> {
        予約.置き場の集まりを見て追加を積む(self.置き場の集まり, 個体, 値)
    }

    /// 型Tを持つ個体群を読む借りを作る。登録していない型は空として読む。
    pub fn 一型を読む借りを作る<T: 個体構成要素>(&self) -> 一型を読む借り<'a, T> {
        let 集まり: &'a 個体構成要素の置き場の集まり = self.置き場の集まり;
        一型を読む借り::生成する(集まり.参照する::<T>())
    }

    /// 型TとUの両方を持つ個体群を読む借りを作る。登録していない型は空として読む。
    pub fn 二型を読む借りを作る<T: 個体構成要素, U: 個体構成要素>(&self) -> 二型を読む借り<'a, T, U> {
        let 集まり: &'a 個体構成要素の置き場の集まり = self.置き場の集まり;
        二型を読む借り::生成する(集まり.参照する::<T>(), 集まり.参照する::<U>())
    }
}
