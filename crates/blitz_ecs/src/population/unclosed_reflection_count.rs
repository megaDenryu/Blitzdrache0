//! 未閉の反映のセッションの件数: 構造変更の反映を始めてまだ閉じていないセッションの本数の勘定。
//! セッションを閉じ忘れた誤りを、個体群の破棄の時点で止めるために置く。
//!
//! 注意: 中の数を外から読む口も書き換える口も開けない。数を直に触れる形にすると、開始と終了が対で呼ばれていなくても
//! 数だけが合う書き方を許してしまう。外が問えるのは「全部閉じているか」だけであり、破れは「到達したらバグ」として panic で止める。
//! 参照: `crates/blitz_render/src/vulkan/unsent_command_buffers.rs`(同じ様式の閉じ忘れ検出の勘定)。

/// 構造変更の反映を始めてまだ閉じていないセッションの件数。
pub(super) struct 未閉の反映のセッションの件数 {
    件数: usize,
}

impl 未閉の反映のセッションの件数 {
    pub(super) fn 零から数え始める() -> Self {
        Self { 件数: 0 }
    }

    pub(super) fn 始めた1件を加える(&mut self) {
        self.件数 += 1;
    }

    pub(super) fn 閉じた1件を差し引く(&mut self) {
        let Some(残りの件数) = self.件数.checked_sub(1) else {
            panic!("反映のセッションを1件も始めていないのに閉じた1件を数えた(開始と終了は対で呼ぶ)")
        };
        self.件数 = 残りの件数;
    }

    pub(super) fn 全部閉じていることを確かめる(&self) {
        if self.件数 != 0 {
            panic!("構造変更の反映のセッションを{}件閉じずに個体群を捨てた(置き場への適用を終えるまでがセッションである)", self.件数)
        }
    }
}
