//! ゲーム世界の個体群が固定する不変条件の試験。生存状態の委譲・登録していない型が空として答えること・
//! 型ごとの件数と占有量の一覧が登録の順で並ぶことを見る。置き場への値の投入は、反映の境界を通さず集まりへ直接行う。

use super::ゲーム世界の個体群;
use crate::liveness_state::個体の生存状態;
use crate::naive_baseline_samples::{見本の位置, 見本の小さな状態};

#[test]
fn 登録していない型への問い合わせは空として答える() {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let 個体 = 個体群.生存台帳.実行時個体IDを発行する();
    assert!(!個体群.個体が型を持っているか::<見本の位置>(個体));
    assert_eq!(個体群.個体の値を参照する::<見本の位置>(個体), None);
    assert!(個体群.型ごとの件数と占有量を一覧する().is_empty());
}

#[test]
fn 生存状態は生存台帳の答えをそのまま返す() {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let 個体 = 個体群.生存台帳.実行時個体IDを発行する();
    assert_eq!(個体群.個体の生存状態を答える(個体), 個体の生存状態::反映待ち);
    assert_eq!(個体群.生存台帳.個体を反映済みにする(個体), Ok(()));
    assert_eq!(個体群.個体の生存状態を答える(個体), 個体の生存状態::生存);
    assert_eq!(個体群.生存している個体の数(), 1);
}

#[test]
fn 型ごとの件数と占有量は登録の順で並ぶ() {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let 甲 = 個体群.生存台帳.実行時個体IDを発行する();
    let 乙 = 個体群.生存台帳.実行時個体IDを発行する();
    assert_eq!(個体群.置き場の集まり.登録して可変に参照する::<見本の小さな状態>().追加する(甲, 見本の小さな状態::生成する(1, false)), Ok(()));
    let 位置の置き場 = 個体群.置き場の集まり.登録して可変に参照する::<見本の位置>();
    assert_eq!(位置の置き場.追加する(甲, 見本の位置::生成する([1.0; 3])), Ok(()));
    assert_eq!(位置の置き場.追加する(乙, 見本の位置::生成する([2.0; 3])), Ok(()));
    let 一覧 = 個体群.型ごとの件数と占有量を一覧する();
    assert_eq!(一覧.len(), 2);
    assert_eq!(一覧[0].型の名前(), std::any::type_name::<見本の小さな状態>());
    assert_eq!(一覧[0].件数(), 1);
    assert_eq!(一覧[1].型の名前(), std::any::type_name::<見本の位置>());
    assert_eq!(一覧[1].件数(), 2);
    assert!(一覧[1].占有量のバイト数() >= 2 * std::mem::size_of::<見本の位置>());
    assert!(個体群.個体が型を持っているか::<見本の位置>(乙));
    assert_eq!(個体群.個体の値を参照する::<見本の位置>(乙), Some(&見本の位置::生成する([2.0; 3])));
}

#[test]
fn 個体の全個体構成要素を取り除くと全部の型から消える() {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let 甲 = 個体群.生存台帳.実行時個体IDを発行する();
    assert_eq!(個体群.置き場の集まり.登録して可変に参照する::<見本の小さな状態>().追加する(甲, 見本の小さな状態::生成する(1, false)), Ok(()));
    assert_eq!(個体群.置き場の集まり.登録して可変に参照する::<見本の位置>().追加する(甲, 見本の位置::生成する([1.0; 3])), Ok(()));
    個体群.置き場の集まり.個体の全個体構成要素を取り除く(甲);
    assert!(!個体群.個体が型を持っているか::<見本の小さな状態>(甲));
    assert!(!個体群.個体が型を持っているか::<見本の位置>(甲));
    assert!(個体群.型ごとの件数と占有量を一覧する().iter().all(|行| 行.件数() == 0));
}
