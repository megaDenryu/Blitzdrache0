//! 実行時個体IDの発行口: 生存台帳のうち、発行だけを外へ貸す狭い口。破棄も反映済み化も持たない。
//! 生存台帳そのものを貸すと外から直接個体を破棄できる口になるため(判断7)、生存台帳を包んで発行だけへ狭める。
//! 発行したIDは同時に予約へ生成として積む。発行だけして積まない経路を作ると、反映も取消しも届かない反映待ちが残る。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断7」。

use super::structural_change::構造変更の予約;
use crate::liveness_ledger::生存台帳;
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

/// 生存台帳から実行時個体IDを発行し、予約へ生成として積むためだけの口。
pub struct 実行時個体IDの発行口<'a> {
    生存台帳: &'a mut 生存台帳,
}

impl<'a> 実行時個体IDの発行口<'a> {
    pub(super) fn 生成する(生存台帳: &'a mut 生存台帳) -> Self {
        Self { 生存台帳 }
    }

    /// 新しい個体の生成を予約へ積み、発行した実行時個体IDを返す。個体は反映まで反映待ちであり問い合わせに現れない。
    pub fn 個体の生成を予約する(&mut self, 予約: &mut 構造変更の予約) -> ゲーム世界の実行時個体ID {
        let 個体 = self.生存台帳.実行時個体IDを発行する();
        予約.生成を積む(個体);
        個体
    }
}
