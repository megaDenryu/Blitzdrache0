//! 借りの型が固定する不変条件の試験。1型と2型の走査がIDの昇順で両方を持つ個体だけを返すこと、
//! 可変の借りで書いた値が読めること、登録していない型の借りが空であり登録もしないこと、読む借りが `&ゲーム世界の個体群` から
//! 同時に複数作れること、同じ型を2度可変に借りると止まることを見る。
//! 置き場への値の投入は、反映の境界を通さず集まりへ直接行う。

use super::ゲーム世界の個体群;
use crate::naive_baseline_samples::{見本の位置, 見本の小さな状態};
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

/// 4個体を発行し、全個体へ位置を、偶数番の個体へ小さな状態を入れる。
fn 位置と状態を持つ個体群を用意する() -> (ゲーム世界の個体群, Vec<ゲーム世界の実行時個体ID>) {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let 個体一覧: Vec<_> = (0..4).map(|_| 個体群.生存台帳.実行時個体IDを発行する()).collect();
    for (番号, 個体) in 個体一覧.iter().enumerate() {
        let 値 = f64::from(u8::try_from(番号).unwrap_or(u8::MAX));
        assert_eq!(個体群.置き場の集まり.登録して可変に参照する::<見本の位置>().追加する(*個体, 見本の位置::生成する([値, 0.0, 0.0])), Ok(()));
        if 番号 % 2 == 0 {
            assert_eq!(個体群.置き場の集まり.登録して可変に参照する::<見本の小さな状態>().追加する(*個体, 見本の小さな状態::生成する(10, true)), Ok(()));
        }
    }
    (個体群, 個体一覧)
}

#[test]
#[allow(non_snake_case)] // 日本語の識別子に含むASCIIの大文字はRustの命名規則の検査に掛かる。ユビキタス言語の登録語をそのまま使う。
fn 一型を読む借りは全個体を実行時個体IDの昇順で返す() {
    let (個体群, 個体一覧) = 位置と状態を持つ個体群を用意する();
    let 借り = 個体群.一型を読む借りを作る::<見本の位置>();
    let 走査した個体一覧: Vec<_> = 借り.IDの昇順で走査する().map(|(個体, _)| 個体).collect();
    assert_eq!(走査した個体一覧, 個体一覧);
    assert_eq!(借り.件数(), 4);
    assert_eq!(借り.参照する(個体一覧[2]).map(見本の位置::成分の和), Some(2.0));
}

#[test]
fn 登録していない型の読む借りは空であり型を登録しない() {
    let 個体群 = ゲーム世界の個体群::生成する();
    let 借り = 個体群.一型を読む借りを作る::<見本の位置>();
    assert_eq!(借り.件数(), 0);
    assert_eq!(借り.IDの昇順で走査する().count(), 0);
    assert_eq!(個体群.二型を読む借りを作る::<見本の位置, 見本の小さな状態>().両方を持つ個体をIDの昇順で走査する().count(), 0);
    assert!(個体群.型ごとの件数と占有量を一覧する().is_empty());
}

#[test]
#[allow(non_snake_case)] // 日本語の識別子に含むASCIIの大文字はRustの命名規則の検査に掛かる。ユビキタス言語の登録語をそのまま使う。
fn 読む借りは共有の参照から同時に複数作れる() {
    let (個体群, 個体一覧) = 位置と状態を持つ個体群を用意する();
    let 個体群の参照: &ゲーム世界の個体群 = &個体群;
    let 位置の借り = 個体群の参照.一型を読む借りを作る::<見本の位置>();
    let もう1つの位置の借り = 個体群の参照.一型を読む借りを作る::<見本の位置>();
    let 状態の借り = 個体群の参照.一型を読む借りを作る::<見本の小さな状態>();
    let 同じ型を2度指す借り = 個体群の参照.二型を読む借りを作る::<見本の位置, 見本の位置>();
    assert_eq!((位置の借り.件数(), もう1つの位置の借り.件数(), 状態の借り.件数()), (4, 4, 2));
    assert_eq!(同じ型を2度指す借り.両方を持つ個体をIDの昇順で走査する().count(), 4);
    assert_eq!(同じ型を2度指す借り.参照する(個体一覧[1]).map(|(甲, 乙)| (甲.成分の和(), 乙.成分の和())), Some((1.0, 1.0)));
}

#[test]
fn 一型を可変に借りる借りで書いた値は読める() {
    let (mut 個体群, 個体一覧) = 位置と状態を持つ個体群を用意する();
    let mut 借り = 個体群.一型を可変に借りる借りを作る::<見本の位置>();
    for (_, 位置) in 借り.IDの昇順で可変に走査する() {
        *位置 = 見本の位置::生成する([1.0, 1.0, 1.0]);
    }
    assert_eq!(借り.参照する(個体一覧[3]).map(見本の位置::成分の和), Some(3.0));
    assert_eq!(個体群.個体の値を参照する::<見本の位置>(個体一覧[3]).map(見本の位置::成分の和), Some(3.0));
}

#[test]
fn 二型を読む借りは両方を持つ個体だけを昇順で返す() {
    let (個体群, 個体一覧) = 位置と状態を持つ個体群を用意する();
    let 借り = 個体群.二型を読む借りを作る::<見本の小さな状態, 見本の位置>();
    let 走査した個体一覧: Vec<_> = 借り.両方を持つ個体をIDの昇順で走査する().map(|(個体, 状態, 位置)| (個体, 状態.残り体力(), 位置.成分の和())).collect();
    assert_eq!(走査した個体一覧, vec![(個体一覧[0], 10, 0.0), (個体一覧[2], 10, 2.0)]);
    assert!(借り.参照する(個体一覧[1]).is_none());
    assert!(借り.参照する(個体一覧[2]).is_some());
}

#[test]
fn 一型を読みもう一型を可変に借りる借りは読む側を見て書く側を変える() {
    let (mut 個体群, 個体一覧) = 位置と状態を持つ個体群を用意する();
    let mut 借り = 個体群.一型を読みもう一型を可変に借りる借りを作る::<見本の小さな状態, 見本の位置>();
    for (_, 状態, 位置) in 借り.両方を持つ個体をIDの昇順で可変に走査する() {
        *位置 = 見本の位置::生成する([f64::from(状態.残り体力()), 0.0, 0.0]);
    }
    assert_eq!(借り.可変に参照する(個体一覧[0]).map(|(_, 位置)| 位置.成分の和()), Some(10.0));
    assert_eq!(個体群.個体の値を参照する::<見本の位置>(個体一覧[1]).map(見本の位置::成分の和), Some(1.0));
}

#[test]
fn 二型を可変に借りる借りは両方を書き換えられる() {
    let (mut 個体群, 個体一覧) = 位置と状態を持つ個体群を用意する();
    let mut 借り = 個体群.二型を可変に借りる借りを作る::<見本の位置, 見本の小さな状態>();
    let mut 走査した件数 = 0;
    for (_, 位置, 状態) in 借り.両方を持つ個体をIDの昇順で可変に走査する() {
        *位置 = 見本の位置::生成する([9.0, 0.0, 0.0]);
        *状態 = 見本の小さな状態::生成する(1, false);
        走査した件数 += 1;
    }
    assert_eq!(走査した件数, 2);
    assert_eq!(借り.参照する(個体一覧[2]).map(|(位置, 状態)| (位置.成分の和(), 状態.残り体力())), Some((9.0, 1)));
    assert!(借り.可変に参照する(個体一覧[1]).is_none());
}

