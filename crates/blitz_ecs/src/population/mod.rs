//! ゲーム世界の個体群: 実行時個体IDと個体構成要素の組み合わせを保持する部分。生存台帳と、型ごとの置き場の集まりを持つ。
//! 個体群への問い合わせは借りの型(`borrowing.rs`)を返し、構造変更は予約の列と反映のセッション(`structural_change`)を通る。
//! この本体が持つのは、生存状態と型ごとの量を答える読みの口と、未閉の反映のセッションの勘定だけである。
//!
//! 注意: 反映のセッションを閉じずに捨てるのは呼び出し側のバグであり、個体群の破棄が未閉の件数を見て panic で止める
//! (規約が定める閉じ忘れ検出の様式)。`Drop` は依存を受け取らず勘定だけを見る。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断5」「判断6」「判断7」。

mod borrowing;
#[cfg(test)]
mod borrowing_tests;
#[cfg(test)]
mod tests;

use crate::component_count::個体構成要素の型ごとの件数と占有量;
use crate::component_marker::個体構成要素;
use crate::liveness_ledger::生存台帳;
use crate::liveness_state::個体の生存状態;
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;
use crate::storage_collection::個体構成要素の置き場の集まり;

/// 実行時個体IDと個体構成要素の組み合わせを保持する、ゲーム世界の個体の集まり。
pub struct ゲーム世界の個体群 {
    生存台帳: 生存台帳,
    置き場の集まり: 個体構成要素の置き場の集まり,
    未閉の反映のセッションの件数: usize,
}

impl ゲーム世界の個体群 {
    /// 個体を1つも持たない個体群を作る。
    pub fn 生成する() -> Self {
        Self {
            生存台帳: 生存台帳::生成する(),
            置き場の集まり: 個体構成要素の置き場の集まり::生成する(),
            未閉の反映のセッションの件数: 0,
        }
    }

    /// 実行時個体IDが指す個体の生存状態を答える。生存台帳へ委譲する。
    pub fn 個体の生存状態を答える(&self, 個体: ゲーム世界の実行時個体ID) -> 個体の生存状態 {
        self.生存台帳.個体の生存状態を答える(個体)
    }

    /// 反映済みで生存している個体の数。
    pub fn 生存している個体の数(&self) -> usize {
        self.生存台帳.生存している個体の数()
    }

    /// 個体が型Tの個体構成要素を持っているか。登録していない型には偽を返す。
    pub fn 個体が型を持っているか<T: 個体構成要素>(&self, 個体: ゲーム世界の実行時個体ID) -> bool {
        self.置き場の集まり.参照する::<T>().is_some_and(|置き場| 置き場.参照する(個体).is_some())
    }

    /// 個体が持つ型Tの値を読む。持っていなければ、また登録していない型なら不在を返す。
    pub fn 個体の値を参照する<T: 個体構成要素>(&self, 個体: ゲーム世界の実行時個体ID) -> Option<&T> {
        self.置き場の集まり.参照する::<T>()?.参照する(個体)
    }

    /// 登録した型ごとの件数と占有量を、登録の順で一覧する(契約26)。
    pub fn 型ごとの件数と占有量を一覧する(&self) -> Vec<個体構成要素の型ごとの件数と占有量> {
        self.置き場の集まり.型ごとの件数と占有量を一覧する()
    }
}

impl Drop for ゲーム世界の個体群 {
    fn drop(&mut self) {
        if self.未閉の反映のセッションの件数 != 0 && !std::thread::panicking() {
            panic!("構造変更の反映のセッションを{}件閉じずに個体群を捨てた(置き場への適用を終えるまでがセッションである)", self.未閉の反映のセッションの件数)
        }
    }
}
