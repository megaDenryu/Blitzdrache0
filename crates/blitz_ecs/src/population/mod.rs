/// 実行時個体IDと個体構成要素の組み合わせを保持する、ゲーム世界の個体の集まり。
pub struct ゲーム世界の個体群 {
    生存台帳: 生存台帳,
    置き場の集まり: 個体構成要素の置き場の集まり,
    未閉の反映のセッションの件数: 未閉の反映のセッションの件数, // 反映のセッションが始まりで増やし終わりで減らす
}

impl ゲーム世界の個体群 {
    /// 個体を1つも持たない個体群を作る。
    pub fn 生成する() -> Self {
        Self {
            生存台帳: 生存台帳::生成する(),
            置き場の集まり: 個体構成要素の置き場の集まり::生成する(),
            未閉の反映のセッションの件数: 未閉の反映のセッションの件数::零から数え始める(),
        }
    }

    /// 実行時個体IDが指す個体の生存状態を答える。生存台帳へ委譲する。
    pub fn 個体の生存状態を答える(&self, 個体: ゲーム世界の実行時個体ID) -> 個体の生存状態 {
        self.生存台帳.個体の生存状態を答える(個体)
    }

    /// 反映済みで生存している個体の数。
    pub fn 生存している個体の数(&self) -> usize {
        self.生存台帳.生存している個体の数()
    }

    /// 個体が型Tの個体構成要素を持っているか。登録していない型には偽を返す。
    pub fn 個体が型を持っているか<T: 個体構成要素>(&self, 個体: ゲーム世界の実行時個体ID) -> bool {
        self.置き場の集まり.参照する::<T>().is_some_and(|置き場| 置き場.参照する(個体).is_some())
    }

    /// 個体が持つ型Tの値を読む。持っていなければ、また登録していない型なら不在を返す。
    pub fn 個体の値を参照する<T: 個体構成要素>(&self, 個体: ゲーム世界の実行時個体ID) -> Option<&T> {
        self.置き場の集まり.参照する::<T>()?.参照する(個体)
    }

    /// 登録した型ごとの件数と占有量を、登録の順で一覧する(契約26)。
    pub fn 型ごとの件数と占有量を一覧する(&self) -> Vec<個体構成要素の型ごとの件数と占有量> {
        self.置き場の集まり.型ごとの件数と占有量を一覧する()
    }
}

impl Drop for ゲーム世界の個体群 {
    fn drop(&mut self) {
        if !std::thread::panicking() {
            self.未閉の反映のセッションの件数.全部閉じていることを確かめる();
        }
    }
}
