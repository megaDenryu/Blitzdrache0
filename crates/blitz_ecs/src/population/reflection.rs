//! ゲーム世界の個体群の、構造変更の境界の口。生成の予約(生存台帳がIDを発行する)と、反映のセッションの開始を持つ。
//! 本体(`mod.rs`)から分けているのは、この2つが反映の境界でだけ呼ばれる局面であるためである(切り出しの根拠義務の条2)。
//!
//! 生成の予約が `&mut self` を要るのは、実行時個体IDを発行できるのが生存台帳だけであり、生存台帳が個体群の持ち物だからである。
//! 追加・削除・破棄の予約は `&ゲーム世界の個体群` と `&mut 構造変更の予約` で積める。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断7」。

use super::structural_change::{構造変更の予約, 構造変更の反映};
use super::ゲーム世界の個体群;
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

impl ゲーム世界の個体群 {
    /// 新しい個体の生成を予約へ積み、発行した実行時個体IDを返す。個体は反映まで反映待ちであり問い合わせに現れない。
    pub fn 個体の生成を予約する(&mut self, 予約: &mut 構造変更の予約) -> ゲーム世界の実行時個体ID {
        let 個体 = self.生存台帳.実行時個体IDを発行する();
        予約.生成を積む(個体);
        個体
    }

    /// 予約の列を置き場へ適用するセッションを始める。返したセッションは `置き場への適用を終える` で必ず閉じる。
    pub fn 構造変更の反映を始める<'a>(&'a mut self, 予約: &'a mut 構造変更の予約) -> 構造変更の反映<'a> {
        構造変更の反映::生成する(self, 予約)
    }
}
