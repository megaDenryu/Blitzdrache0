//! 構造変更の予約の取消しと、捨てたときの検出が固定する不変条件の試験。取り消した生成の個体が失効してスロットが再利用されること、
//! 命令を積んだまま捨てた予約が止まること、反映か取消しを通った予約は捨てても止まらないこと、取り消した予約を使い回しても同じ列の記憶が残っていないことを見る。

use super::reservation::構造変更の予約;
use crate::liveness_state::個体の生存状態;
use crate::naive_baseline_samples::見本の位置;
use crate::population::ゲーム世界の個体群;

#[test]
fn 取り消した生成の個体は失効し次の発行が同じスロットを再利用する() {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let 個体 = 個体群.個体の生成を予約する(&mut 予約);
    assert_eq!(予約.追加を予約する(&個体群, 個体, 見本の位置::生成する([1.0; 3])), Ok(()));
    予約.積んだ命令を取り消す(&mut 個体群);
    assert_eq!(個体群.個体の生存状態を答える(個体), 個体の生存状態::失効);
    assert_eq!((個体群.生存している個体の数(), 予約.積んだ命令の件数()), (0, 0));
    assert!(個体群.型ごとの件数と占有量を一覧する().is_empty());
    let 次の個体 = 個体群.個体の生成を予約する(&mut 予約);
    assert_eq!(次の個体.スロットの添字(), 個体.スロットの添字());
    assert_eq!(次の個体.世代(), 個体.世代() + 1);
    assert_eq!(個体群.構造変更の反映を始める(&mut 予約).置き場への適用を終える().反映した生成の件数(), 1);
}

#[test]
#[should_panic(expected = "反映も取消しも通っていない構造変更の予約が1件の命令を積んだまま捨てられた")]
fn 生成を予約したまま予約を捨てると止まる() {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let _個体 = 個体群.個体の生成を予約する(&mut 予約);
    drop(予約);
}

#[test]
fn 反映か取消しを通った予約は捨てても止まらない() {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 反映した予約 = 構造変更の予約::生成する();
    let _個体 = 個体群.個体の生成を予約する(&mut 反映した予約);
    assert_eq!(個体群.構造変更の反映を始める(&mut 反映した予約).置き場への適用を終える().反映した生成の件数(), 1);
    drop(反映した予約);
    let mut 取り消した予約 = 構造変更の予約::生成する();
    let _個体 = 個体群.個体の生成を予約する(&mut 取り消した予約);
    取り消した予約.積んだ命令を取り消す(&mut 個体群);
    drop(取り消した予約);
}

#[test]
fn 取り消した予約を使い回しても同じ列に積んだ追加の記憶は残っていない() {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let 個体 = 個体群.個体の生成を予約する(&mut 予約);
    assert_eq!(予約.追加を予約する(&個体群, 個体, 見本の位置::生成する([1.0; 3])), Ok(()));
    予約.積んだ命令を取り消す(&mut 個体群);
    assert_eq!(予約.追加を予約する(&個体群, 個体, 見本の位置::生成する([2.0; 3])), Ok(()));
    assert!(予約.追加を予約する(&個体群, 個体, 見本の位置::生成する([3.0; 3])).is_err());
    予約.積んだ命令を取り消す(&mut 個体群);
    assert_eq!(予約.積んだ命令の件数(), 0);
}
