//! 構造変更の予約の `Drop`: 反映も取消しも通らずに命令を積んだまま捨てられた予約を panic で止める。
//! 本体(`reservation.rs`)から分けているのは外部トレイトの実装であるためである(切り出しの根拠義務の条1)。
//!
//! 反映を通った予約は命令の列が必ず空になり(`apply.rs` の `drain(..)`)、取消しも空にする。したがって命令の列が空でないまま
//! 捨てられた予約は、反映も取消しも通っていない予約と一対一に対応し、この判定は外部の情報を要らない。生成を予約した個体が
//! 生存台帳に反映待ちのまま残り、再利用もされないという痕跡がこの経路でだけ生まれるため、「到達したらバグ」として止める。
//! 参照: `crates/blitz_ecs/src/population/unclosed_reflection_count.rs`(同じ様式の閉じ忘れ検出)。

use super::reservation::構造変更の予約;

impl Drop for 構造変更の予約 {
    fn drop(&mut self) {
        if !std::thread::panicking() && !self.命令一覧.is_empty() {
            panic!("反映も取消しも通っていない構造変更の予約が{}件の命令を積んだまま捨てられた(予約は反映か取消しで空にしてから捨てる)", self.命令一覧.len())
        }
    }
}
