//! 構造変更の反映の、命令の種類ごとの適用の工程。セッション本体(`session.rs`)から分けているのは、この3つの工程が
//! 「予約の命令の列を読み、個体群の生存台帳と置き場の集まりを書き、結果へ数える」という同じ形の連なりであり、
//! 本体は口の提供と工程の順序だけを持つためである(切り出しの根拠義務の条5)。
//! 受け取るのは結果の勘定であり、返すのは無い(個体群と予約はセッションが持つ)。
//!
//! 生存していない個体へ向いた命令と持っていない型への削除は捨てて数える(契約21)。置き場が拒む追加は予約の時点で
//! 止めているため、ここで拒まれるのは不変条件の破れであり panic で止める。

use super::command::構造変更の命令;
use super::result::構造変更の反映の結果;
use super::session::構造変更の反映;
use crate::erased_storage::型を消した取り除きの結果;
use crate::liveness_state::個体の生存状態;

impl 構造変更の反映<'_> {
    pub(super) fn 生成を適用する(&mut self, 結果: &mut 構造変更の反映の結果) {
        for 命令 in &self.予約.命令一覧 {
            let 構造変更の命令::生成(個体) = 命令 else {
                continue;
            };
            match self.個体群.生存台帳.個体を反映済みにする(*個体) {
                Ok(()) => 結果.生成を数える(),
                Err(_失効か反映済み) => 結果.捨てたものを数える(),
            }
        }
    }

    pub(super) fn 追加と削除を適用して破棄を集める(&mut self, 結果: &mut 構造変更の反映の結果) {
        for 命令 in self.予約.命令一覧.drain(..) {
            match 命令 {
                構造変更の命令::生成(_) => {}
                構造変更の命令::破棄(個体) => self.予約.破棄の作業列.push(個体),
                構造変更の命令::追加 { 個体, 値 } => {
                    if self.個体群.生存台帳.個体の生存状態を答える(個体) != 個体の生存状態::生存 {
                        結果.捨てたものを数える();
                        continue;
                    }
                    let 型の名前 = 値.型の名前();
                    if 値.置き場へ入れる(&mut self.個体群.置き場の集まり, 個体).is_err() {
                        panic!("個体{個体:?}への型{型の名前}の追加が反映で拒まれた(予約の時点の検査が2つ目の追加を止める)")
                    }
                    結果.追加を数える();
                }
                構造変更の命令::削除 { 個体, 型 } => {
                    let 生存しているか = self.個体群.生存台帳.個体の生存状態を答える(個体) == 個体の生存状態::生存;
                    let 取り除きの結果 = self.個体群.置き場の集まり.型を消したまま可変に参照する(型).map(|置き場| 置き場.個体の値を取り除く(個体));
                    match (生存しているか, 取り除きの結果) {
                        (true, Some(型を消した取り除きの結果::取り除いた)) => 結果.削除を数える(),
                        (true, Some(型を消した取り除きの結果::持っていなかった) | None) | (false, _) => 結果.捨てたものを数える(),
                    }
                }
            }
        }
    }

    pub(super) fn 破棄を適用する(&mut self, 結果: &mut 構造変更の反映の結果) {
        for 個体 in self.予約.破棄の作業列.drain(..) {
            match self.個体群.生存台帳.個体を破棄する(個体) {
                Ok(()) => {
                    self.個体群.置き場の集まり.個体の全個体構成要素を取り除く(個体);
                    結果.破棄を数える();
                }
                Err(_失効) => 結果.捨てたものを数える(),
            }
        }
    }
}
