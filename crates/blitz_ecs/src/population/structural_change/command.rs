//! 構造変更の命令: 予約の列の1件。名前を持つ4つの命令(生成・破棄・追加・削除)の列挙であり、追加の値は型を消した箱で運ぶ。
//! 反映は積んだ順でなく命令の種類で固定した順(生成 → 追加と削除 → 破棄)で適用する。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断7」。

use std::any::TypeId;

use super::erased_value::型を消した個体構成要素の値;
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

pub(crate) enum 構造変更の命令 {
    生成(ゲーム世界の実行時個体ID),
    破棄(ゲーム世界の実行時個体ID),
    追加 {
        個体: ゲーム世界の実行時個体ID,
        値: Box<dyn 型を消した個体構成要素の値>,
    },
    削除 {
        個体: ゲーム世界の実行時個体ID,
        型: TypeId,
    },
}
