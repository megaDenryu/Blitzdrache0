//! 構造変更の反映: 予約の列を置き場へ適用する2段のセッション型(判断7)。`個体群.構造変更の反映を始める(予約)` が返し、
//! 消える個体の一覧と、その個体が持つ個体構成要素を型ごとに読み出す口を持つ。外の工程(剛体の台帳・空間索引への口を持つ側)は
//! ここで外部基盤の登録を解除し(契約18)、`置き場への適用を終える` で置き場を書き換える。
//!
//! 注意: 閉じずに捨てると個体群の破棄が未閉の件数を見て panic で止める。`Drop` には載せない(依存を受け取れない)。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断7」。

use super::command::構造変更の命令;
use super::reservation::構造変更の予約;
use super::result::構造変更の反映の結果;
use crate::component_marker::個体構成要素;
use crate::liveness_state::個体の生存状態;
use crate::population::ゲーム世界の個体群;
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

/// 予約の列を置き場へ適用する途中の状態。始めたら必ず `置き場への適用を終える` で閉じる。
#[must_use = "構造変更の反映は置き場への適用を終えるまでがセッションである(閉じずに捨てると個体群の破棄が止まる)"]
pub struct 構造変更の反映<'a> {
    pub(super) 個体群: &'a mut ゲーム世界の個体群,
    pub(super) 予約: &'a mut 構造変更の予約,
}

impl<'a> 構造変更の反映<'a> {
    pub(crate) fn 生成する(個体群: &'a mut ゲーム世界の個体群, 予約: &'a mut 構造変更の予約) -> Self {
        個体群.未閉の反映のセッションの件数.始めた1件を加える();
        Self { 個体群, 予約 }
    }

    /// この反映で消える個体(破棄を予約された、まだ失効していない個体)を、積んだ順で列挙する。
    pub fn 消える個体を列挙する(&self) -> impl Iterator<Item = ゲーム世界の実行時個体ID> + '_ {
        self.予約
            .命令一覧
            .iter()
            .filter_map(|命令| match 命令 {
                構造変更の命令::破棄(個体) => Some(*個体),
                構造変更の命令::生成(_) | 構造変更の命令::追加 { .. } | 構造変更の命令::削除 { .. } => None,
            })
            .filter(|個体| self.個体群.個体の生存状態を答える(*個体) != 個体の生存状態::失効)
    }

    /// 消える個体が持つ型Tの値を、置き場を書き換える前に読む。持っていなければ不在を返す。
    pub fn 消える個体の値を参照する<T: 個体構成要素>(&self, 個体: ゲーム世界の実行時個体ID) -> Option<&T> {
        self.個体群.個体の値を参照する::<T>(個体)
    }

    /// 予約の列を命令の種類の順(生成 → 追加と削除 → 破棄)で置き場へ適用し、触った置き場の密な列を添字の昇順へ並べ直して閉じる。
    pub fn 置き場への適用を終える(mut self) -> 構造変更の反映の結果 {
        let mut 結果 = 構造変更の反映の結果::default();
        self.生成を適用する(&mut 結果);
        self.追加と削除を適用して破棄を集める(&mut 結果);
        self.破棄を適用する(&mut 結果);
        self.予約.この列に積んだ追加の記憶を消す();
        self.個体群.置き場の集まり.全部の密な列を添字の昇順へ並べ直す();
        self.個体群.未閉の反映のセッションの件数.閉じた1件を差し引く();
        結果
    }
}
