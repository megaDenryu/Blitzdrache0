//! 構造変更の予約: 処理の途中の生成・破棄・個体構成要素の追加と削除を、反映の境界まで積む命令の列(契約17)。
//! 個体群とは別の型であり、処理は `&ゲーム世界の個体群`(または借りの型)と `&mut 構造変更の予約` を同時に借りられる。
//! 生成の予約だけは生存台帳がIDを発行するため個体群の口(`個体の生成を予約する`)を通り、この型は発行済みのIDを積む。
//!
//! 同じ個体の同じ型への2つ目の追加は、置き場の現状と、この列に既に積んだ追加の両方を見て、積む時点で拒む。
//! 反映は失敗しない操作だけになり、一部だけ適用された置き場は生まれない。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断7」。

use std::any::TypeId;
use std::collections::HashSet;

use super::command::構造変更の命令;
use super::error::構造変更の予約エラー;
use crate::component_marker::個体構成要素;
use crate::population::ゲーム世界の個体群;
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

/// 同じ列に積んだ追加を、個体と型の組で覚えるための鍵。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
struct 個体と型の組 {
    個体: ゲーム世界の実行時個体ID,
    型: TypeId,
}

/// 反映の境界まで積んでおく構造変更の命令の列。
pub struct 構造変更の予約 {
    pub(super) 命令一覧: Vec<構造変更の命令>,
    この列に積んだ追加の記憶: HashSet<個体と型の組>,
    pub(super) 破棄の作業列: Vec<ゲーム世界の実行時個体ID>, // 反映が命令の種類で順序を固定するために使い回す一時の列
}

impl Default for 構造変更の予約 {
    fn default() -> Self {
        Self::生成する()
    }
}

impl 構造変更の予約 {
    /// 何も積んでいない予約を作る。
    pub fn 生成する() -> Self {
        Self {
            命令一覧: Vec::new(),
            この列に積んだ追加の記憶: HashSet::new(),
            破棄の作業列: Vec::new(),
        }
    }

    /// 個体の破棄を積む。失効した個体への破棄は正常として受け付け、反映が捨てて数える。
    pub fn 破棄を予約する(&mut self, 個体: ゲーム世界の実行時個体ID) {
        self.命令一覧.push(構造変更の命令::破棄(個体));
    }

    /// 個体への型Tの追加を積む。置き場が既に持っているか、この列に既に積んであれば拒む(契約11)。
    pub fn 追加を予約する<T: 個体構成要素>(&mut self, 個体群: &ゲーム世界の個体群, 個体: ゲーム世界の実行時個体ID, 値: T) -> Result<(), 構造変更の予約エラー> {
        let 型の名前 = std::any::type_name::<T>();
        if 個体群.個体が型を持っているか::<T>(個体) {
            return Err(構造変更の予約エラー::置き場が既に同じ型を持っている { 個体, 型の名前 });
        }
        if !self.この列に積んだ追加の記憶.insert(個体と型の組 { 個体, 型: TypeId::of::<T>() }) {
            return Err(構造変更の予約エラー::同じ列に既に追加が積まれている { 個体, 型の名前 });
        }
        self.命令一覧.push(構造変更の命令::追加 { 個体, 値: Box::new(値) });
        Ok(())
    }

    /// 個体からの型Tの削除を積む。持っていない型と失効した個体への削除は正常として受け付け、反映が捨てて数える。
    pub fn 削除を予約する<T: 個体構成要素>(&mut self, 個体: ゲーム世界の実行時個体ID) {
        self.命令一覧.push(構造変更の命令::削除 { 個体, 型: TypeId::of::<T>() });
    }

    /// 積んである命令の数。
    pub fn 積んだ命令の件数(&self) -> usize {
        self.命令一覧.len()
    }

    pub(crate) fn 生成を積む(&mut self, 個体: ゲーム世界の実行時個体ID) {
        self.命令一覧.push(構造変更の命令::生成(個体));
    }

    /// この列に積んだ追加の記憶を消す。反映が命令を取り出した後に呼ぶ。命令の列の確保した容量は次の予約のために残る。
    pub(super) fn この列に積んだ追加の記憶を消す(&mut self) {
        self.この列に積んだ追加の記憶.clear();
    }
}
