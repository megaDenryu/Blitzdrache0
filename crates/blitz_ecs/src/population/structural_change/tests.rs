//! 構造変更の予約と反映が固定する不変条件の試験。生成と追加が反映の境界で一括で確定すること、反映前は現れないこと、
//! 破棄で全個体構成要素が消え古いIDが空になること、同じ境界での生成と追加と破棄の共存、2つ目の追加の予約時エラー、
//! 失効した個体への追加が捨てられて数えられること、消える個体の口、セッションの閉じ忘れの検出を見る。

use super::error::構造変更の予約エラー;
use super::reservation::構造変更の予約;
use crate::liveness_state::個体の生存状態;
use crate::naive_baseline_samples::{見本の位置, 見本の小さな状態};
use crate::population::ゲーム世界の個体群;
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

/// 位置を持つ生存した個体を1つ作って反映する。
fn 位置を持つ個体を1つ反映する(個体群: &mut ゲーム世界の個体群, 予約: &mut 構造変更の予約) -> ゲーム世界の実行時個体ID {
    let 個体 = 個体群.個体の生成を予約する(予約);
    assert_eq!(予約.追加を予約する(個体群, 個体, 見本の位置::生成する([1.0, 2.0, 3.0])), Ok(()));
    let 結果 = 個体群.構造変更の反映を始める(予約).置き場への適用を終える();
    assert_eq!((結果.反映した生成の件数(), 結果.反映した追加の件数(), 結果.捨てた件数()), (1, 1, 0));
    個体
}

#[test]
fn 生成と追加は反映の境界で一括で確定し反映前は現れない() {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let 個体 = 個体群.個体の生成を予約する(&mut 予約);
    assert_eq!(予約.追加を予約する(&個体群, 個体, 見本の位置::生成する([1.0, 2.0, 3.0])), Ok(()));
    assert_eq!(個体群.個体の生存状態を答える(個体), 個体の生存状態::反映待ち);
    assert_eq!(個体群.一型を読む借りを作る::<見本の位置>().件数(), 0);
    let 結果 = 個体群.構造変更の反映を始める(&mut 予約).置き場への適用を終える();
    assert_eq!(結果.反映した生成の件数(), 1);
    assert_eq!(個体群.個体の生存状態を答える(個体), 個体の生存状態::生存);
    assert_eq!(個体群.一型を読む借りを作る::<見本の位置>().参照する(個体).map(見本の位置::成分の和), Some(6.0));
    assert_eq!(予約.積んだ命令の件数(), 0);
}

#[test]
#[allow(non_snake_case)] // 日本語の識別子に含むASCIIの大文字はRustの命名規則の検査に掛かる。ユビキタス言語の登録語をそのまま使う。
fn 破棄の反映で全個体構成要素が消え古いIDでの読みは空になる() {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let 個体 = 位置を持つ個体を1つ反映する(&mut 個体群, &mut 予約);
    assert_eq!(予約.追加を予約する(&個体群, 個体, 見本の小さな状態::生成する(3, true)), Ok(()));
    assert_eq!(個体群.構造変更の反映を始める(&mut 予約).置き場への適用を終える().反映した追加の件数(), 1);
    予約.破棄を予約する(個体);
    let 反映 = 個体群.構造変更の反映を始める(&mut 予約);
    assert_eq!(反映.消える個体を列挙する().collect::<Vec<_>>(), vec![個体]);
    assert_eq!(反映.消える個体の値を参照する::<見本の小さな状態>(個体).map(見本の小さな状態::残り体力), Some(3));
    assert_eq!(反映.置き場への適用を終える().反映した破棄の件数(), 1);
    assert_eq!(個体群.個体の生存状態を答える(個体), 個体の生存状態::失効);
    assert!(個体群.個体の値を参照する::<見本の位置>(個体).is_none());
    assert!(個体群.個体の値を参照する::<見本の小さな状態>(個体).is_none());
    assert!(個体群.型ごとの件数と占有量を一覧する().iter().all(|行| 行.件数() == 0));
}

#[test]
fn 同じ境界での生成と追加と破棄は矛盾なく共存する() {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let 先の個体 = 位置を持つ個体を1つ反映する(&mut 個体群, &mut 予約);
    予約.破棄を予約する(先の個体);
    let 後の個体 = 個体群.個体の生成を予約する(&mut 予約);
    assert_eq!(予約.追加を予約する(&個体群, 後の個体, 見本の位置::生成する([4.0, 5.0, 6.0])), Ok(()));
    let 一瞬の個体 = 個体群.個体の生成を予約する(&mut 予約);
    assert_eq!(予約.追加を予約する(&個体群, 一瞬の個体, 見本の位置::生成する([0.0; 3])), Ok(()));
    予約.破棄を予約する(一瞬の個体);
    let 結果 = 個体群.構造変更の反映を始める(&mut 予約).置き場への適用を終える();
    assert_eq!((結果.反映した生成の件数(), 結果.反映した追加の件数(), 結果.反映した破棄の件数(), 結果.捨てた件数()), (2, 2, 2, 0));
    let 走査した個体一覧: Vec<_> = 個体群.一型を読む借りを作る::<見本の位置>().IDの昇順で走査する().map(|(個体, _)| 個体).collect();
    assert_eq!(走査した個体一覧, vec![後の個体]);
    assert_eq!(個体群.生存している個体の数(), 1);
}

#[test]
fn 同じ個体の同じ型への2つ目の追加は予約の時点で型付きエラーで返る() {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let 個体 = 位置を持つ個体を1つ反映する(&mut 個体群, &mut 予約);
    let 置き場の側の結果 = 予約.追加を予約する(&個体群, 個体, 見本の位置::生成する([0.0; 3]));
    assert!(matches!(置き場の側の結果, Err(構造変更の予約エラー::置き場が既に同じ型を持っている { 個体: 拒んだ個体, .. }) if 拒んだ個体 == 個体));
    assert_eq!(予約.追加を予約する(&個体群, 個体, 見本の小さな状態::生成する(1, false)), Ok(()));
    let 列の側の結果 = 予約.追加を予約する(&個体群, 個体, 見本の小さな状態::生成する(2, false));
    assert!(matches!(列の側の結果, Err(構造変更の予約エラー::同じ列に既に追加が積まれている { .. })));
    assert_eq!(予約.積んだ命令の件数(), 1);
}

#[test]
fn 失効した個体への追加と削除は捨てられて数えられる() {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let 個体 = 位置を持つ個体を1つ反映する(&mut 個体群, &mut 予約);
    予約.破棄を予約する(個体);
    assert_eq!(個体群.構造変更の反映を始める(&mut 予約).置き場への適用を終える().反映した破棄の件数(), 1);
    assert_eq!(予約.追加を予約する(&個体群, 個体, 見本の小さな状態::生成する(1, false)), Ok(()));
    予約.削除を予約する::<見本の位置>(個体);
    予約.破棄を予約する(個体);
    let 結果 = 個体群.構造変更の反映を始める(&mut 予約).置き場への適用を終える();
    assert_eq!(結果.捨てた件数(), 3);
    assert_eq!((結果.反映した追加の件数(), 結果.反映した削除の件数(), 結果.反映した破棄の件数()), (0, 0, 0));
}

