//! 構造変更の予約が積む時点で拒む要求。同じ個体の同じ型への2つ目の追加(契約11)を、置き場の現状と同じ列に積まれた追加の
//! 両方を見て拒む。失効した個体への追加と削除は正常であり(契約21)、ここでは拒まず反映が捨てた件数を数える。

use thiserror::Error;

use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

/// 追加の予約を積む時点で拒む要求。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 構造変更の予約エラー {
    /// 置き場がその個体のその型を既に持っている。
    #[error("個体{個体:?}は既に型{型の名前}を持っている(同じ型の2つ目は予約できない)")]
    置き場が既に同じ型を持っている {
        /// 拒んだ相手の個体。
        個体: ゲーム世界の実行時個体ID,
        /// 追加しようとした型の、人が読む名前。
        型の名前: &'static str,
    },
    /// 同じ予約の列に、その個体のその型への追加が既に積まれている。
    #[error("個体{個体:?}への型{型の名前}の追加は同じ予約の列に既に積まれている(同じ型の2つ目は予約できない)")]
    同じ列に既に追加が積まれている {
        /// 拒んだ相手の個体。
        個体: ゲーム世界の実行時個体ID,
        /// 追加しようとした型の、人が読む名前。
        型の名前: &'static str,
    },
}
