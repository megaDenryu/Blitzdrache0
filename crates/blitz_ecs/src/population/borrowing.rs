//! ゲーム世界の個体群が借りの型を作る口。`&mut ゲーム世界の個体群` が現れるのはこの5つのメソッドだけであり、
//! 個体群に作用する処理は借りの型を引数で受け、個体群そのものを受け取らない。
//! 本体(`mod.rs`)から分けているのは、この5つだけが置き場の集まりへ型を登録し、それを貸す操作であるためである(切り出しの根拠義務の条3)。
//! 触るフィールドは置き場の集まりだけであり、読む借りも `&mut self` を要るのは、登録していない型を空の置き場として登録してから貸すためである。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断6」。

use super::ゲーム世界の個体群;
use crate::borrow::{一型を可変に借りる借り, 一型を読みもう一型を可変に借りる借り, 一型を読む借り, 二型を可変に借りる借り, 二型を読む借り};
use crate::component_marker::個体構成要素;

impl ゲーム世界の個体群 {
    /// 型Tを持つ個体群を読む借りを作る。
    pub fn 一型を読む借りを作る<T: 個体構成要素>(&mut self) -> 一型を読む借り<'_, T> {
        一型を読む借り::生成する(self.置き場の集まり.登録して可変に参照する::<T>())
    }

    /// 型Tを持つ個体群を読み書きする借りを作る。
    pub fn 一型を可変に借りる借りを作る<T: 個体構成要素>(&mut self) -> 一型を可変に借りる借り<'_, T> {
        一型を可変に借りる借り::生成する(self.置き場の集まり.登録して可変に参照する::<T>())
    }

    /// 型TとUの両方を持つ個体群を読む借りを作る。同じ型を2度指す要求は panic で止める。
    pub fn 二型を読む借りを作る<T: 個体構成要素, U: 個体構成要素>(&mut self) -> 二型を読む借り<'_, T, U> {
        let (甲, 乙) = self.置き場の集まり.二つを登録して可変に参照する::<T, U>();
        二型を読む借り::生成する(甲, 乙)
    }

    /// 型Tを読み型Uを書き換える、両方を持つ個体群の借りを作る。同じ型を2度指す要求は panic で止める。
    pub fn 一型を読みもう一型を可変に借りる借りを作る<T: 個体構成要素, U: 個体構成要素>(&mut self) -> 一型を読みもう一型を可変に借りる借り<'_, T, U> {
        let (甲, 乙) = self.置き場の集まり.二つを登録して可変に参照する::<T, U>();
        一型を読みもう一型を可変に借りる借り::生成する(甲, 乙)
    }

    /// 型TとUの両方を持つ個体群を読み書きする借りを作る。同じ型を2度可変に借りる要求は panic で止める。
    pub fn 二型を可変に借りる借りを作る<T: 個体構成要素, U: 個体構成要素>(&mut self) -> 二型を可変に借りる借り<'_, T, U> {
        let (甲, 乙) = self.置き場の集まり.二つを登録して可変に参照する::<T, U>();
        二型を可変に借りる借り::生成する(甲, 乙)
    }
}
