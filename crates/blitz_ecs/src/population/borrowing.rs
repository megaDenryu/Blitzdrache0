//! ゲーム世界の個体群が借りの型を作る口。個体群に作用する処理へ渡すのは借りの型であり、個体群そのものは渡さない。
//! 本体(`mod.rs`)から分けているのは、この5つが置き場の集まりを借りの型へ包んで貸す操作であり、触るフィールドが置き場の集まりだけであるためである(切り出しの根拠義務の条3)。
//!
//! 読む借り2つは `&self` から作る。登録していない型は登録せず、置き場の不在を空として読む。読む処理が読む依存として表現できることは
//! ゲーム実行基盤の処理の実行契約(設計正本の判断6が指す上位の正本)の要求であり、置き場の都合(遅延の登録)をそこへ漏らさない。
//! 可変の借り3つは `&mut self` を要り、登録していない型を空の置き場として登録してから貸す。書く処理は書く依存である。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断6」。

use super::ゲーム世界の個体群;
use crate::borrow::{一型を可変に借りる借り, 一型を読みもう一型を可変に借りる借り, 一型を読む借り, 二型を可変に借りる借り, 二型を読む借り};
use crate::component_marker::個体構成要素;

impl ゲーム世界の個体群 {
    /// 型Tを持つ個体群を読む借りを作る。登録していない型は空として読み、登録しない。
    pub fn 一型を読む借りを作る<T: 個体構成要素>(&self) -> 一型を読む借り<'_, T> {
        一型を読む借り::生成する(self.置き場の集まり.参照する::<T>())
    }

    /// 型Tを持つ個体群を読み書きする借りを作る。
    pub fn 一型を可変に借りる借りを作る<T: 個体構成要素>(&mut self) -> 一型を可変に借りる借り<'_, T> {
        一型を可変に借りる借り::生成する(self.置き場の集まり.登録して可変に参照する::<T>())
    }

    /// 型TとUの両方を持つ個体群を読む借りを作る。登録していない型は空として読み、登録しない。読む借りは同じ型を2度指してよい。
    pub fn 二型を読む借りを作る<T: 個体構成要素, U: 個体構成要素>(&self) -> 二型を読む借り<'_, T, U> {
        二型を読む借り::生成する(self.置き場の集まり.参照する::<T>(), self.置き場の集まり.参照する::<U>())
    }

    /// 型Tを読み型Uを書き換える、両方を持つ個体群の借りを作る。同じ型を2度指す要求は panic で止める。
    pub fn 一型を読みもう一型を可変に借りる借りを作る<T: 個体構成要素, U: 個体構成要素>(&mut self) -> 一型を読みもう一型を可変に借りる借り<'_, T, U> {
        let (甲, 乙) = self.置き場の集まり.二つを登録して可変に参照する::<T, U>();
        一型を読みもう一型を可変に借りる借り::生成する(甲, 乙)
    }

    /// 型TとUの両方を持つ個体群を読み書きする借りを作る。同じ型を2度可変に借りる要求は panic で止める。
    pub fn 二型を可変に借りる借りを作る<T: 個体構成要素, U: 個体構成要素>(&mut self) -> 二型を可変に借りる借り<'_, T, U> {
        let (甲, 乙) = self.置き場の集まり.二つを登録して可変に参照する::<T, U>();
        二型を可変に借りる借り::生成する(甲, 乙)
    }
}
