//! 読みながら構造変更を予約する借りが固定する不変条件の試験。読む借りを保持したまま生成と追加を予約でき、
//! 借りを落として反映すると追加が反映されていること、借りの口で予約した追加も置き場の現状を見て2つ目を拒むことを見る。

use super::structural_change::構造変更の予約;
use super::ゲーム世界の個体群;
use crate::naive_baseline_samples::{見本の位置, 見本の小さな状態};
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

/// 位置を持つ生存した個体を2つ作って反映する。
fn 位置を持つ個体を2つ反映する(個体群: &mut ゲーム世界の個体群, 予約: &mut 構造変更の予約) -> Vec<ゲーム世界の実行時個体ID> {
    let 個体一覧: Vec<_> = (0..2).map(|_| 個体群.個体の生成を予約する(予約)).collect();
    for (番号, 個体) in 個体一覧.iter().enumerate() {
        let 値 = f64::from(u8::try_from(番号).unwrap_or(u8::MAX));
        assert_eq!(予約.追加を予約する(個体群, *個体, 見本の位置::生成する([値, 0.0, 0.0])), Ok(()));
    }
    assert_eq!(個体群.構造変更の反映を始める(予約).置き場への適用を終える().反映した生成の件数(), 2);
    個体一覧
}

#[test]
fn 読む借りを保持したまま生成と追加を予約し反映すると追加が反映されている() {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let 元の個体一覧 = 位置を持つ個体を2つ反映する(&mut 個体群, &mut 予約);
    let mut 生まれた個体一覧 = Vec::new();
    {
        let mut 借り = 個体群.読みながら構造変更を予約する借りを作る();
        let 位置の借り = 借り.一型を読む借りを作る::<見本の位置>();
        for (元の個体, 位置) in 位置の借り.IDの昇順で走査する() {
            let 新しい個体 = 借り.個体の生成を予約する(&mut 予約);
            assert_eq!(借り.追加を予約する(&mut 予約, 新しい個体, 見本の位置::生成する([位置.成分の和() + 10.0, 0.0, 0.0])), Ok(()));
            assert_eq!(借り.追加を予約する(&mut 予約, 元の個体, 見本の小さな状態::生成する(7, true)), Ok(()));
            生まれた個体一覧.push(新しい個体);
        }
        assert_eq!(借り.二型を読む借りを作る::<見本の位置, 見本の小さな状態>().両方を持つ個体をIDの昇順で走査する().count(), 0);
    }
    let 結果 = 個体群.構造変更の反映を始める(&mut 予約).置き場への適用を終える();
    assert_eq!((結果.反映した生成の件数(), 結果.反映した追加の件数(), 結果.捨てた件数()), (2, 4, 0));
    assert_eq!(個体群.生存している個体の数(), 4);
    assert_eq!(個体群.個体の値を参照する::<見本の位置>(生まれた個体一覧[1]).map(見本の位置::成分の和), Some(11.0));
    assert_eq!(個体群.個体の値を参照する::<見本の小さな状態>(元の個体一覧[0]).map(見本の小さな状態::残り体力), Some(7));
}

#[test]
fn 借りの口で予約した追加も置き場の現状を見て2つ目を拒む() {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let 個体一覧 = 位置を持つ個体を2つ反映する(&mut 個体群, &mut 予約);
    let 借り = 個体群.読みながら構造変更を予約する借りを作る();
    assert!(借り.追加を予約する(&mut 予約, 個体一覧[0], 見本の位置::生成する([0.0; 3])).is_err());
    assert_eq!(予約.積んだ命令の件数(), 0);
}
