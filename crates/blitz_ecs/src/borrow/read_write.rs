//! 一型を読みもう一型を可変に借りる借り: 型Tの置き場への共有の参照と型Uの置き場への可変の参照を持ち、
//! 両方を持つ個体のIDの昇順の走査と個別の読み書きを提供する。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断6」。

use super::merge_walk::実行時個体IDの昇順の合流走査;
use crate::component_marker::個体構成要素;
use crate::component_storage::個体構成要素の置き場;
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

/// 型Tを読み、型Uを書き換えるための、両方を持つ個体群の借り。
pub struct 一型を読みもう一型を可変に借りる借り<'a, T: 個体構成要素, U: 個体構成要素> {
    読む置き場: &'a 個体構成要素の置き場<T>,
    書く置き場: &'a mut 個体構成要素の置き場<U>,
}

impl<'a, T: 個体構成要素, U: 個体構成要素> 一型を読みもう一型を可変に借りる借り<'a, T, U> {
    pub(crate) fn 生成する(読む置き場: &'a 個体構成要素の置き場<T>, 書く置き場: &'a mut 個体構成要素の置き場<U>) -> Self {
        Self { 読む置き場, 書く置き場 }
    }

    /// 個体が持つ両方の値を読む。どちらかを持っていなければ不在を返す。
    pub fn 参照する(&self, 個体: ゲーム世界の実行時個体ID) -> Option<(&T, &U)> {
        Some((self.読む置き場.参照する(個体)?, self.書く置き場.参照する(個体)?))
    }

    /// 個体が持つ型Tの値を読み、型Uの値を可変に貸す。どちらかを持っていなければ不在を返す。
    pub fn 可変に参照する(&mut self, 個体: ゲーム世界の実行時個体ID) -> Option<(&T, &mut U)> {
        Some((self.読む置き場.参照する(個体)?, self.書く置き場.可変に参照する(個体)?))
    }

    /// 両方を持つ全個体を実行時個体IDの昇順で走査し、型Uの値を可変に貸す。
    #[allow(non_snake_case)] // 日本語の識別子に含むASCIIの大文字はRustの命名規則の検査に掛かる。ユビキタス言語の登録語をそのまま使う。
    pub fn 両方を持つ個体をIDの昇順で可変に走査する(&mut self) -> impl Iterator<Item = (ゲーム世界の実行時個体ID, &T, &mut U)> {
        実行時個体IDの昇順の合流走査::生成する(self.読む置き場.IDの昇順で走査する(), self.書く置き場.IDの昇順で可変に走査する())
    }
}
