//! 二型を読む借り: 型TとUの置き場への共有の参照を持ち、両方を持つ個体のIDの昇順の走査と個別の読みを提供する。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断6」。

use super::merge_walk::実行時個体IDの昇順の合流走査;
use crate::component_marker::個体構成要素;
use crate::component_storage::個体構成要素の置き場;
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

/// 型TとUの両方を持つ個体群を読むための借り。
pub struct 二型を読む借り<'a, T: 個体構成要素, U: 個体構成要素> {
    甲の置き場: &'a 個体構成要素の置き場<T>,
    乙の置き場: &'a 個体構成要素の置き場<U>,
}

impl<'a, T: 個体構成要素, U: 個体構成要素> 二型を読む借り<'a, T, U> {
    pub(crate) fn 生成する(甲の置き場: &'a 個体構成要素の置き場<T>, 乙の置き場: &'a 個体構成要素の置き場<U>) -> Self {
        Self { 甲の置き場, 乙の置き場 }
    }

    /// 個体が持つ両方の値を読む。どちらかを持っていなければ不在を返す。
    pub fn 参照する(&self, 個体: ゲーム世界の実行時個体ID) -> Option<(&'a T, &'a U)> {
        Some((self.甲の置き場.参照する(個体)?, self.乙の置き場.参照する(個体)?))
    }

    /// 両方を持つ全個体を実行時個体IDの昇順で走査する。
    #[allow(non_snake_case)] // 日本語の識別子に含むASCIIの大文字はRustの命名規則の検査に掛かる。ユビキタス言語の登録語をそのまま使う。
    pub fn 両方を持つ個体をIDの昇順で走査する(&self) -> impl Iterator<Item = (ゲーム世界の実行時個体ID, &'a T, &'a U)> {
        実行時個体IDの昇順の合流走査::生成する(self.甲の置き場.IDの昇順で走査する(), self.乙の置き場.IDの昇順で走査する())
    }
}
