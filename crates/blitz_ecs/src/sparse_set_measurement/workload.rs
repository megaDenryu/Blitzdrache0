//! 疎な集合の計測の項目が1回ずつ走らせる5つの仕事と、その下ごしらえ。どれも計測の外で個体群と予約を用意し、
//! 測る区間だけを`Instant`で囲む。この計測は予約と反映の境界を通す本番の経路で測るため、反映の費用を含む。
//! このモジュールの関数は計測の項目の列挙だけが呼ぶ工程であり、依存を持たず自分で状態を組み立てるため、外へ運ぶものが無い。
//!
//! 注意: 走査の結果は`black_box`へ渡す。渡さないと最適化が走査ごと消し、0に近い数字が出る。

use std::hint::black_box;
use std::time::{Duration, Instant};

use crate::naive_baseline_samples::{見本の位置, 見本の小さな状態};
use crate::population::structural_change::構造変更の予約;
use crate::population::ゲーム世界の個体群;
use crate::runtime_entity_id::ゲーム世界の実行時個体ID;

pub(super) fn 一体ずつの生成と破棄の所要時間を測る(個体数: u32) -> Duration {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let 開始 = Instant::now();
    for _ in 0..個体数 {
        let 個体 = 個体群.個体の生成を予約する(&mut 予約);
        追加の予約が通ることを確かめる(予約.追加を予約する(&個体群, 個体, 見本の位置::生成する([1.0, 2.0, 3.0])));
        black_box(個体群.構造変更の反映を始める(&mut 予約).置き場への適用を終える());
        予約.破棄を予約する(個体);
        black_box(個体群.構造変更の反映を始める(&mut 予約).置き場への適用を終える());
    }
    開始.elapsed()
}

pub(super) fn まとめての生成と破棄の所要時間を測る(個体数: u32) -> Duration {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let 開始 = Instant::now();
    let 個体一覧 = 位置を持つ個体を用意する(&mut 個体群, &mut 予約, 個体数);
    for 個体 in &個体一覧 {
        予約.破棄を予約する(*個体);
    }
    black_box(個体群.構造変更の反映を始める(&mut 予約).置き場への適用を終える());
    開始.elapsed()
}

pub(super) fn 一つの型の走査の所要時間を測る(個体数: u32) -> Duration {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let _個体一覧 = 位置を持つ個体を用意する(&mut 個体群, &mut 予約, 個体数);
    let 借り = 個体群.一型を読む借りを作る::<見本の位置>();
    let 開始 = Instant::now();
    let mut 合計 = 0.0_f64;
    for (_, 位置) in 借り.IDの昇順で走査する() {
        合計 += 位置.成分の和();
    }
    let 所要時間 = 開始.elapsed();
    black_box(合計);
    所要時間
}

pub(super) fn 二つの型の問い合わせの所要時間を測る(個体数: u32) -> Duration {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let 個体一覧 = 位置を持つ個体を用意する(&mut 個体群, &mut 予約, 個体数);
    小さな状態を1つ飛ばしで足す(&mut 個体群, &mut 予約, &個体一覧);
    let 借り = 個体群.二型を読む借りを作る::<見本の位置, 見本の小さな状態>();
    let 開始 = Instant::now();
    let mut 合計 = 0.0_f64;
    for (_, 位置, 状態) in 借り.両方を持つ個体をIDの昇順で走査する() {
        合計 += 位置.成分の和() + f64::from(状態.残り体力());
    }
    let 所要時間 = 開始.elapsed();
    black_box(合計);
    所要時間
}

pub(super) fn 追加と削除の所要時間を測る(個体数: u32) -> Duration {
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let 個体一覧 = 位置を持つ個体を用意する(&mut 個体群, &mut 予約, 個体数);
    let 開始 = Instant::now();
    小さな状態を1つ飛ばしで足す(&mut 個体群, &mut 予約, &個体一覧);
    for 個体 in 個体一覧.iter().step_by(2) {
        予約.削除を予約する::<見本の小さな状態>(*個体);
    }
    black_box(個体群.構造変更の反映を始める(&mut 予約).置き場への適用を終える());
    開始.elapsed()
}

/// 個体数ぶんの個体を生成し、全個体へ位置を足して、1回の反映で確定する。
pub(super) fn 位置を持つ個体を用意する(個体群: &mut ゲーム世界の個体群, 予約: &mut 構造変更の予約, 個体数: u32) -> Vec<ゲーム世界の実行時個体ID> {
    let mut 個体一覧 = Vec::new();
    for 番号 in 0..個体数 {
        let 個体 = 個体群.個体の生成を予約する(予約);
        let 値 = f64::from(番号 % 1000);
        追加の予約が通ることを確かめる(予約.追加を予約する(個体群, 個体, 見本の位置::生成する([値, 値 + 1.0, 値 + 2.0])));
        個体一覧.push(個体);
    }
    black_box(個体群.構造変更の反映を始める(予約).置き場への適用を終える());
    個体一覧
}

/// 偶数番の個体へ小さな状態を足して、1回の反映で確定する。
pub(super) fn 小さな状態を1つ飛ばしで足す(個体群: &mut ゲーム世界の個体群, 予約: &mut 構造変更の予約, 個体一覧: &[ゲーム世界の実行時個体ID]) {
    for 個体 in 個体一覧.iter().step_by(2) {
        追加の予約が通ることを確かめる(予約.追加を予約する(個体群, *個体, 見本の小さな状態::生成する(100, true)));
    }
    black_box(個体群.構造変更の反映を始める(予約).置き場への適用を終える());
}

fn 追加の予約が通ることを確かめる<E: std::fmt::Debug>(結果: Result<(), E>) {
    if let Err(拒んだ理由) = 結果 {
        panic!("計測の下ごしらえの追加の予約を拒まれた: {拒んだ理由:?}")
    }
}
