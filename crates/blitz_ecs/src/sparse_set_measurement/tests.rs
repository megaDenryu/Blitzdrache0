//! 疎な集合の置き場の5項目を1万と10万の個体で測って1行ずつ出力する試験と、10万個体での型ごとの占有量を出力する試験。
//! `#[ignore]`を付けているのは、この計測が普段の検証(`cargo xtask verify`)の時間を延ばさないためである。
//! 走らせ方: `cargo test -p blitz_ecs --release -- --ignored --nocapture`。
//! 最適化の無いデバッグの数字は比較の材料にならないため、`--release`で走らせる。

use super::workload::{位置を持つ個体を用意する, 小さな状態を1つ飛ばしで足す};
use super::疎な集合の計測の項目;
use crate::population::structural_change::構造変更の予約;
use crate::population::ゲーム世界の個体群;

const 計測する個体数一覧: [u32; 2] = [10_000, 100_000];
const 占有量を仮定する型の数: usize = 37;

#[test]
#[ignore = "計測専用。--ignored を付けたときだけ走らせる"]
fn 疎な集合の五項目を1万と10万の個体で計測する() {
    for 個体数 in 計測する個体数一覧 {
        for 項目 in 疎な集合の計測の項目::全項目 {
            項目.三回走らせて中央値を採る(個体数).結果を1行で出力する();
        }
    }
}

#[test]
#[ignore = "計測専用。--ignored を付けたときだけ走らせる"]
fn 疎な集合の占有量を10万個体で計測する() {
    let 個体数 = 100_000;
    let mut 個体群 = ゲーム世界の個体群::生成する();
    let mut 予約 = 構造変更の予約::生成する();
    let 個体一覧 = 位置を持つ個体を用意する(&mut 個体群, &mut 予約, 個体数);
    小さな状態を1つ飛ばしで足す(&mut 個体群, &mut 予約, &個体一覧);
    let mut 合計のバイト数 = 0;
    for 行 in 個体群.型ごとの件数と占有量を一覧する() {
        println!("疎な集合 占有量 型={} 件数={} バイト数={}", 行.型の名前(), 行.件数(), 行.占有量のバイト数());
        合計のバイト数 += 行.占有量のバイト数();
    }
    let 疎な配列の1枠のバイト数 = std::mem::size_of::<Option<u32>>();
    let 疎な配列だけの1型あたりのバイト数 = 疎な配列の1枠のバイト数 * usize::try_from(個体数).unwrap_or(usize::MAX);
    println!(
        "疎な集合 占有量 2型の合計バイト数={} 疎な配列だけの1型あたりバイト数={} {}型ぶんの疎な配列のバイト数={}",
        合計のバイト数,
        疎な配列だけの1型あたりのバイト数,
        占有量を仮定する型の数,
        疎な配列だけの1型あたりのバイト数 * 占有量を仮定する型の数
    );
}
