//! 疎な集合の置き場の計測。素朴な置き場と同じ4項目(生成と破棄・1型の走査・2型の問い合わせ・追加と削除)に、
//! 全部を生かしてからまとめて破棄する形の生成と破棄を足した5項目を、項目ごとに3回走らせて中央値を採る。
//! 占有量は所要時間でなくバイト数であるため、項目の列挙とは別の試験で出す。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断8」。

mod report_row;
mod tests;
mod workload;

use std::time::Duration;

use report_row::疎な集合の計測の結果の行;

/// 疎な集合の置き場について測る5つの項目。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 疎な集合の計測の項目 {
    一体ずつの生成と破棄,
    まとめての生成と破棄,
    一つの型の走査,
    二つの型の問い合わせ,
    個体構成要素の追加と削除,
}

impl 疎な集合の計測の項目 {
    pub(crate) const 全項目: [疎な集合の計測の項目; 5] = [
        疎な集合の計測の項目::一体ずつの生成と破棄,
        疎な集合の計測の項目::まとめての生成と破棄,
        疎な集合の計測の項目::一つの型の走査,
        疎な集合の計測の項目::二つの型の問い合わせ,
        疎な集合の計測の項目::個体構成要素の追加と削除,
    ];

    /// 3回走らせ、所要時間の中央値を1行の記録にして返す。3回にするのは、最初の1回に入る確保の揺れを外すためである。
    pub(crate) fn 三回走らせて中央値を採る(self, 個体数: u32) -> 疎な集合の計測の結果の行 {
        let mut 所要時間一覧 = [self.一度走らせる(個体数), self.一度走らせる(個体数), self.一度走らせる(個体数)];
        所要時間一覧.sort_unstable();
        疎な集合の計測の結果の行::生成する(self.名前(), 個体数, 所要時間一覧[1])
    }

    fn 名前(self) -> &'static str {
        match self {
            疎な集合の計測の項目::一体ずつの生成と破棄 => "生成と破棄(1体ずつ反映)",
            疎な集合の計測の項目::まとめての生成と破棄 => "生成と破棄(全部生かしてまとめて破棄)",
            疎な集合の計測の項目::一つの型の走査 => "1型の走査",
            疎な集合の計測の項目::二つの型の問い合わせ => "2型の問い合わせ",
            疎な集合の計測の項目::個体構成要素の追加と削除 => "追加と削除",
        }
    }

    fn 一度走らせる(self, 個体数: u32) -> Duration {
        match self {
            疎な集合の計測の項目::一体ずつの生成と破棄 => workload::一体ずつの生成と破棄の所要時間を測る(個体数),
            疎な集合の計測の項目::まとめての生成と破棄 => workload::まとめての生成と破棄の所要時間を測る(個体数),
            疎な集合の計測の項目::一つの型の走査 => workload::一つの型の走査の所要時間を測る(個体数),
            疎な集合の計測の項目::二つの型の問い合わせ => workload::二つの型の問い合わせの所要時間を測る(個体数),
            疎な集合の計測の項目::個体構成要素の追加と削除 => workload::追加と削除の所要時間を測る(個体数),
        }
    }
}
