//! 個体構成要素の標識となる`trait`。メソッドも関連型も関連定数も持たず、上位の境界(`Send + Sync + 'static`)が
//! 契約2(借用を含まない)・契約3(別のスレッドへ渡せる)・契約4(複数のスレッドから同時に読める)を束ねる。
//! `'static` は、型を消した置き場から具体の置き場を `std::any::Any` で復元するための要求でもある。
//!
//! 注意: 全称の実装(`impl<T> 個体構成要素 for T`)を書かない。書き手が実装を1行書くことが、その型を
//! 個体構成要素として登録してよいという意思表示であり(契約8)、全称の実装はその認可を消す。
//! 参照: `_doc/設計/ゲーム世界の個体群の基盤.md`「判断4」。

/// ゲーム世界の個体を構成する型であることの認可。実装を1行書くことが、その型を置き場へ入れてよいという意思表示である。
pub trait 個体構成要素: Send + Sync + 'static {}
