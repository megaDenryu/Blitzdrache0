//! 経路の開閉と旅行者の歩行の更新の工程(`経路の開閉と旅行者の歩行の進行`)が受け取り、返す値。始めるための指定と、1刻みに与える入力と、1刻み進めた結果と、その中の失敗である。
//! 工程の本体と分けるのは、本体が進行の状態と1刻みの手順を持ち、こちらが工程の外から入り外へ出る値の形だけを持つためである(`区域の中の移動の型.rs` と同じ分け方)。

use blitz_design::{MParameter, M不変データ, M値オブジェクト, M関数への入力};

use super::経路の開閉と旅行者の歩行の進行;
use crate::traveler::{旅行者の出来事, 旅行者の意図, 歩行の規則};
use crate::traveler_error::歩行の失敗;
use crate::地点と経路::指定の失敗::経路の指定の失敗;
use crate::地点と経路::開閉の出来事::経路の開閉の出来事;
use crate::地点と経路::開閉の命令::経路の開閉の命令;
use crate::地点と経路::開閉の状態::経路の開閉の状態;
use crate::地点と経路::開閉の規則::経路の開閉の規則;
use crate::居場所::旅行者の居場所;

/// 経路の開閉と旅行者の歩行の進行を始めるための指定。開閉の状態は、その規則から作ったものを渡す。
#[derive(Clone)]
pub struct 経路の開閉と旅行者の歩行の進行の指定 {
    pub 開閉の規則: 経路の開閉の規則,
    pub 開閉の状態: 経路の開閉の状態,
    pub 居場所: 旅行者の居場所,
    pub 身体: 歩行の規則,
}

impl M不変データ for 経路の開閉と旅行者の歩行の進行の指定 {}
impl M関数への入力 for 経路の開閉と旅行者の歩行の進行の指定 {}
impl MParameter for 経路の開閉と旅行者の歩行の進行の指定 {}

/// 1刻みに与える入力。開閉の命令(出来事から作られる)と、旅行者の意図である。
#[derive(Debug, Clone, PartialEq)]
pub struct 経路の開閉と旅行者の歩行の更新への入力 {
    pub 開閉の命令: 経路の開閉の命令,
    pub 旅行者の意図: 旅行者の意図,
}

impl M不変データ for 経路の開閉と旅行者の歩行の更新への入力 {}
impl M関数への入力 for 経路の開閉と旅行者の歩行の更新への入力 {}
impl MParameter for 経路の開閉と旅行者の歩行の更新への入力 {}
impl M値オブジェクト for 経路の開閉と旅行者の歩行の更新への入力 {}

/// 1刻みで2つの遷移のどちらかが失敗した理由。
#[derive(Debug, Clone, PartialEq)]
pub enum 経路の開閉と旅行者の歩行の更新の失敗 {
    開閉を遷移できなかった(経路の指定の失敗),
    歩行を遷移できなかった(歩行の失敗),
}

impl M不変データ for 経路の開閉と旅行者の歩行の更新の失敗 {}
impl M値オブジェクト for 経路の開閉と旅行者の歩行の更新の失敗 {}

/// 1刻み進めた結果。次の進行と、その刻みで生じた出来事と、失敗した遷移の理由を持つ。
pub struct 経路の開閉と旅行者の歩行の更新の結果 {
    pub 次の進行: 経路の開閉と旅行者の歩行の進行,
    pub 開閉の出来事一覧: Vec<経路の開閉の出来事>,
    pub 旅行者の出来事一覧: Vec<旅行者の出来事>,
    pub 失敗一覧: Vec<経路の開閉と旅行者の歩行の更新の失敗>,
}
