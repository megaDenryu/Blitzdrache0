//! 経路の開閉と旅行者の歩行の遷移(`経路の開閉と旅行者の歩行の状態::経路の開閉と旅行者の歩行を1回更新する`)が受け取る命令の組と規則と、返す出来事。
//! 遷移の本体と分けるのは、本体が状態と1刻みの手順を持ち、こちらが遷移の外から入り外へ出る値の形だけを持つためである(`区域の中の移動の型.rs` と同じ分け方)。

use blitz_design::{Mイベント, M不変データ, M値オブジェクト, M命令の組, M規則, M遷移が受け取る命令};

use crate::traveler_error::歩行の失敗;
use crate::地点と経路::指定の失敗::経路の指定の失敗;
use crate::地点と経路::開閉の出来事::経路の開閉の出来事;
use crate::地点と経路::開閉の命令::経路の開閉の命令;
use crate::地点と経路::開閉の規則::経路の開閉の規則;
use crate::旅行者::{旅行者の出来事, 旅行者の意図, 歩行の規則};

/// 1刻みに与える入力。開閉の命令(出来事から作られる)と、旅行者の意図である。2つの `Mコマンド` だけを並べた構造体であるため、`MParameter` でなく `M命令の組` を名乗る。
#[derive(Debug, Clone, PartialEq)]
pub struct 経路の開閉と旅行者の歩行の更新への入力 {
    開閉の命令: 経路の開閉の命令,
    旅行者の意図: 旅行者の意図,
}

impl M不変データ for 経路の開閉と旅行者の歩行の更新への入力 {}
impl M遷移が受け取る命令 for 経路の開閉と旅行者の歩行の更新への入力 {}
impl M命令の組 for 経路の開閉と旅行者の歩行の更新への入力 {}
impl M値オブジェクト for 経路の開閉と旅行者の歩行の更新への入力 {}

impl 経路の開閉と旅行者の歩行の更新への入力 {
    pub fn 生成する(開閉の命令: 経路の開閉の命令, 旅行者の意図: 旅行者の意図) -> Self {
        Self { 開閉の命令, 旅行者の意図 }
    }

    pub fn 開閉の命令(&self) -> &経路の開閉の命令 {
        &self.開閉の命令
    }

    pub fn 旅行者の意図(&self) -> 旅行者の意図 {
        self.旅行者の意図
    }
}

/// 経路の開閉と旅行者の歩行の遷移へ読み取り専用で与える規則。地図を持つ開閉の規則と、旅行者の身体の歩行の規則である。
/// 歩行の遷移の空間制約(いま通れる通り口)は、状態の経路の開閉から刻みごとに導くため、この規則に持たない。
#[derive(Clone)]
pub struct 経路の開閉と旅行者の歩行の規則 {
    開閉の規則: 経路の開閉の規則,
    身体: 歩行の規則,
}

impl M不変データ for 経路の開閉と旅行者の歩行の規則 {}
impl M規則 for 経路の開閉と旅行者の歩行の規則 {}

impl 経路の開閉と旅行者の歩行の規則 {
    pub fn 生成する(開閉の規則: 経路の開閉の規則, 身体: 歩行の規則) -> Self {
        Self { 開閉の規則, 身体 }
    }

    pub fn 開閉の規則(&self) -> &経路の開閉の規則 {
        &self.開閉の規則
    }

    pub fn 身体(&self) -> &歩行の規則 {
        &self.身体
    }
}

/// 経路の開閉と旅行者の歩行の1刻みで成立した事実。2つの遷移の出来事と、片方の遷移が失敗して、その刻みにそちらが進まなかった事実である。
/// 片方の遷移の失敗をこの遷移の失敗にしないのは、2つの遷移を互いに独立に進めるためである(門は旅行者の失敗に関わらず予定どおりに閉じる)。
/// 片方の失敗を、その遷移の失敗の値のまま、この遷移の語彙の出来事として表す(設計オントロジー 3.5.9 の、失敗を別の系へ伝えるときは呼び出し側が自分の語彙で表すという規則による)。
#[derive(Debug, Clone, PartialEq)]
pub enum 経路の開閉と旅行者の歩行の出来事 {
    /// 開閉の遷移で成立した事実。
    開閉の出来事(経路の開閉の出来事),
    /// 歩行の遷移で成立した事実。
    旅行者の出来事(旅行者の出来事),
    /// 開閉の遷移が命令を拒み、この刻みに経路の開閉が変わらなかった事実。
    開閉を遷移できなかった(経路の指定の失敗),
    /// 歩行の遷移が失敗し、この刻みに旅行者の居場所が変わらなかった事実。
    歩行を遷移できなかった(歩行の失敗),
}

impl M不変データ for 経路の開閉と旅行者の歩行の出来事 {}
impl Mイベント for 経路の開閉と旅行者の歩行の出来事 {}
