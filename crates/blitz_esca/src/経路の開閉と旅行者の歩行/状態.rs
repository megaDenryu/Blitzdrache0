//! 経路の開閉と旅行者の歩行の状態と、その1刻みの遷移(`M遷移関数`)。状態は経路の開閉の状態と旅行者の居場所の組である。
//!
//! 1刻みの順序は「開閉を遷移する → 通れる通り口を導く → 歩行を遷移する」である。この順序は、門が閉じる刻みに旅行者が門を通ろうとした場合の結果を決める。
//! 閉じる刻みの歩行は、閉じた後の通り口で判断され、門で遮られる。
//! 通れる通り口は、開閉を遷移した後の開閉の状態から毎刻み導き、規則が持つ地図と組んだ読み口(`区域の空間制約の読み口`)で歩行を進める。
//! 導いた値を状態にも規則にも持たないのは、経路の開閉の状態が旅行者が歩けるかどうかの正本であり、導いた値を並べて持つと正本が2つになるためである。
//! 読み口で地図を借りるのは、歩行の規則(`歩行遷移の規則`)を毎刻み作ると地図の複製が毎刻みかかるためである。
//!
//! 2つの遷移の失敗は互いに独立に扱う。開閉の遷移が命令を拒んでも開閉の状態はそのまま歩行を進め、歩行の遷移が失敗しても開閉の遷移の結果は残す。
//! 片方の失敗は、この遷移の出来事(`開閉を遷移できなかった`・`歩行を遷移できなかった`)として返す。両方が失敗した刻みも、受け取った状態を次の状態とし、2つの出来事を返す。
//! この遷移が失敗するのは、受け取った開閉の状態の経路が規則の地図に無く、通れる通り口を導けないときだけである。その刻みは歩行を評価できず、有効な次の状態を作れない。
//! そのとき開閉の遷移も同じ理由で失敗しており、受け取った開閉の状態をそのまま返しているため、受け取った状態を書き換えずに遷移失敗結果へ入れられる。
//! 開閉の遷移が成功したなら、状態と命令の経路は地図で確かめ済みであり、通れる通り口は必ず導ける。

use blitz_design::{M不変データ, M状態, M遷移関数, 遷移失敗結果, 遷移成功結果};

use super::経路の開閉と旅行者の歩行の更新の型::{経路の開閉と旅行者の歩行の出来事, 経路の開閉と旅行者の歩行の更新への入力, 経路の開閉と旅行者の歩行の規則};
use crate::transition_parameter::遷移パラメータ;
use crate::地点と経路::指定の失敗::経路の指定の失敗;
use crate::地点と経路::空間制約の読み口::区域の空間制約の読み口;
use crate::地点と経路::開閉の状態::経路の開閉の状態;
use crate::居場所::旅行者の居場所;

/// 経路の開閉の状態と旅行者の居場所の組。
#[derive(Debug, Clone, PartialEq)]
pub struct 経路の開閉と旅行者の歩行の状態 {
    開閉の状態: 経路の開閉の状態,
    居場所: 旅行者の居場所,
}

impl M不変データ for 経路の開閉と旅行者の歩行の状態 {}
impl M状態 for 経路の開閉と旅行者の歩行の状態 {}

impl 経路の開閉と旅行者の歩行の状態 {
    /// 開閉の状態と居場所から状態を作る。開閉の状態の経路が規則の地図に在るかは、遷移が規則の地図で確かめる。
    pub fn 生成する(開閉の状態: 経路の開閉の状態, 居場所: 旅行者の居場所) -> Self {
        Self { 開閉の状態, 居場所 }
    }

    pub fn 開閉の状態(&self) -> &経路の開閉の状態 {
        &self.開閉の状態
    }

    pub fn 居場所(&self) -> &旅行者の居場所 {
        &self.居場所
    }

    /// 状態を値で受け取り、開閉を遷移し、遷移した後の開閉の状態から通れる通り口を導き、歩行を遷移する純粋計算(M遷移関数の型シグネチャを満たす)。
    pub fn 経路の開閉と旅行者の歩行を1回更新する(
        self,
        入力: &経路の開閉と旅行者の歩行の更新への入力,
        規則: &経路の開閉と旅行者の歩行の規則,
        パラメータ: 遷移パラメータ,
    ) -> Result<遷移成功結果<Self, 経路の開閉と旅行者の歩行の出来事>, 遷移失敗結果<Self, 経路の指定の失敗>> {
        let (開閉の状態, mut 出来事一覧) = match self.開閉の状態.開閉を遷移する(入力.開閉の命令(), 規則.開閉の規則(), パラメータ) {
            Ok(成功) => (成功.次の状態, 成功.出来事一覧.into_iter().map(経路の開閉と旅行者の歩行の出来事::開閉の出来事).collect()),
            Err(失敗) => (失敗.元の状態, vec![経路の開閉と旅行者の歩行の出来事::開閉を遷移できなかった(失敗.失敗の理由)]),
        };
        let 通れる通り口 = match 開閉の状態.通れる通り口を導く(規則.開閉の規則().地図()) {
            Ok(通れる通り口) => 通れる通り口,
            Err(失敗の理由) => {
                return Err(遷移失敗結果 {
                    元の状態: Self { 開閉の状態, 居場所: self.居場所 },
                    失敗の理由,
                });
            }
        };
        let 空間制約 = 区域の空間制約の読み口::生成する(規則.開閉の規則().地図(), &通れる通り口);
        let 居場所 = match self.居場所.空間制約の読み口で歩行を遷移する(&入力.旅行者の意図(), 規則.身体(), 空間制約, パラメータ) {
            Ok(成功) => {
                出来事一覧.extend(成功.出来事一覧.into_iter().map(経路の開閉と旅行者の歩行の出来事::旅行者の出来事));
                成功.次の状態
            }
            Err(失敗) => {
                出来事一覧.push(経路の開閉と旅行者の歩行の出来事::歩行を遷移できなかった(失敗.失敗の理由));
                失敗.元の状態
            }
        };
        Ok(遷移成功結果 {
            次の状態: Self { 開閉の状態, 居場所 },
            出来事一覧,
        })
    }
}

// 経路の開閉と旅行者の歩行を1回更新する が遷移の役割(M状態・M命令の組・M規則 から M状態・Mイベント、失敗は型付きエラー)を満たすことをコンパイラに確かめさせる。
const _: M遷移関数<経路の開閉と旅行者の歩行の状態, 経路の開閉と旅行者の歩行の更新への入力, 経路の開閉と旅行者の歩行の規則, 遷移パラメータ, 経路の開閉と旅行者の歩行の出来事, 経路の指定の失敗> =
    M遷移関数::生成する(経路の開閉と旅行者の歩行の状態::経路の開閉と旅行者の歩行を1回更新する);
