//! 経路の開閉と旅行者の歩行の状態と、その1刻みの状態遷移(`M状態遷移関数`)。状態は経路の開閉の状態と旅行者の居場所の組である。
//!
//! 1刻みの順序は「開閉を状態遷移させる → 歩行の規則を組む → 歩行を状態遷移させる」である。この順序は、門が閉じる刻みに旅行者が門を通ろうとした場合の結果を決める。
//! 閉じる刻みの歩行は、閉じた後の通り口で判断され、門で遮られる。
//! 歩行は、宣言のある状態遷移 `旅行者の居場所::歩行を状態遷移させる` で進める。その規則(`歩行の状態遷移の規則`)は、開閉の規則が共有する地図(`Arc`)と、開閉を状態遷移させた後の開閉の状態から刻みごとに組む。
//! 地図は `M共有される不変データ` であり、組むときに複製せず `Arc` の数を1つ増やすだけである。開閉の状態は規則へ値で移し、歩行の後に規則から取り出して次の状態へ戻すため、複製しない。
//! 通り口が開いているかは読むときに開閉の状態へ問う。通れる通り口を並べた値を状態にも規則にも持たないのは、経路の開閉の状態が旅行者が歩けるかどうかの正本であり、並べて持つと正本が2つになるためである。
//!
//! この状態遷移は失敗しない。開閉の状態遷移と歩行の状態遷移がどちらも失敗しないためである。地図に無い経路・地図に無い地点・区域の外の居場所・有限でない現在地は、
//! ゲームの規則として起きることではなく、壊れた状態か命令を渡したプログラムの誤りでしか起きないため、2つの状態遷移が停止する(2026-09-28 オーナー裁定。設計オントロジー 3.5.9)。
//! 開閉の状態遷移が状態と命令の経路を規則の地図で確かめた後であるため、開閉を状態遷移させた後の状態からは必ず空間制約を作れる。

use std::convert::Infallible;

use blitz_design::{M不変データ, M状態, M状態遷移関数, 状態遷移失敗結果, 状態遷移成功結果};

use super::経路の開閉と旅行者の歩行の更新の型::{経路の開閉と旅行者の歩行の出来事, 経路の開閉と旅行者の歩行の更新への入力, 経路の開閉と旅行者の歩行の規則};
use crate::transition_parameter::状態遷移パラメータ;
use crate::地点と経路::開閉の状態::経路の開閉の状態;
use crate::居場所::旅行者の居場所;
use crate::歩行の状態遷移::歩行の状態遷移の規則;

/// 経路の開閉の状態と旅行者の居場所の組。
#[derive(Debug, Clone, PartialEq)]
pub struct 経路の開閉と旅行者の歩行の状態 {
    開閉の状態: 経路の開閉の状態,
    居場所: 旅行者の居場所,
}

impl M不変データ for 経路の開閉と旅行者の歩行の状態 {}
impl M状態 for 経路の開閉と旅行者の歩行の状態 {}

impl 経路の開閉と旅行者の歩行の状態 {
    /// 開閉の状態と居場所から状態を作る。開閉の状態の経路が規則の地図に在るかは、状態遷移が規則の地図で確かめる。
    pub fn 生成する(開閉の状態: 経路の開閉の状態, 居場所: 旅行者の居場所) -> Self {
        Self { 開閉の状態, 居場所 }
    }

    pub fn 開閉の状態(&self) -> &経路の開閉の状態 {
        &self.開閉の状態
    }

    pub fn 居場所(&self) -> &旅行者の居場所 {
        &self.居場所
    }

    /// 状態を値で受け取り、開閉を状態遷移させ、状態遷移した後の開閉の状態と規則の地図から組んだ歩行の規則で歩行を状態遷移させる純粋計算(M状態遷移関数の型シグネチャを満たす)。失敗しない状態遷移である。
    pub fn 経路の開閉と旅行者の歩行を1回更新する(
        self,
        入力: &経路の開閉と旅行者の歩行の更新への入力,
        規則: &経路の開閉と旅行者の歩行の規則,
        パラメータ: 状態遷移パラメータ,
    ) -> Result<状態遷移成功結果<Self, 経路の開閉と旅行者の歩行の出来事>, 状態遷移失敗結果<Self, Infallible>> {
        let 開閉 = match self.開閉の状態.開閉を状態遷移させる(入力.開閉の命令(), 規則.開閉の規則(), パラメータ) {
            Ok(成功) => 成功,
            Err(失敗) => match 失敗.失敗の理由 {},
        };
        let 空間制約 = 規則
            .開閉の規則()
            .空間制約を作る(開閉.次の状態)
            .unwrap_or_else(|失敗| panic!("開閉を状態遷移させた後の状態から空間制約を作れない(開閉の状態遷移は規則の地図に在る経路だけを状態に持つ): {失敗}"));
        let 歩行の規則 = 歩行の状態遷移の規則::生成する(*規則.身体(), 空間制約);
        let 歩行 = match self.居場所.歩行を状態遷移させる(&入力.旅行者の意図(), &歩行の規則, パラメータ) {
            Ok(成功) => 成功,
            Err(失敗) => match 失敗.失敗の理由 {},
        };
        let 開閉の出来事一覧 = 開閉.出来事一覧.into_iter().map(経路の開閉と旅行者の歩行の出来事::開閉の出来事);
        let 旅行者の出来事一覧 = 歩行.出来事一覧.into_iter().map(経路の開閉と旅行者の歩行の出来事::旅行者の出来事);
        Ok(状態遷移成功結果 {
            次の状態: Self {
                開閉の状態: 歩行の規則.開閉の状態を取り出す(),
                居場所: 歩行.次の状態,
            },
            出来事一覧: 開閉の出来事一覧.chain(旅行者の出来事一覧).collect(),
        })
    }
}

// 経路の開閉と旅行者の歩行を1回更新する が状態遷移の役割(M状態・M命令の組・M規則 から M状態・Mイベント、失敗しない)を満たすことをコンパイラに確かめさせる。
const _: M状態遷移関数<経路の開閉と旅行者の歩行の状態, 経路の開閉と旅行者の歩行の更新への入力, 経路の開閉と旅行者の歩行の規則, 状態遷移パラメータ, 経路の開閉と旅行者の歩行の出来事, std::convert::Infallible> =
    M状態遷移関数::生成する(経路の開閉と旅行者の歩行の状態::経路の開閉と旅行者の歩行を1回更新する);
