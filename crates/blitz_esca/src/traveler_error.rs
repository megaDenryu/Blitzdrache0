//! 旅行者の現在地と歩行の規則の生成が失敗する理由。破られた不変条件を選択肢で数え上げ、文で言う。

use blitz_math::{メートル, メートル毎秒};

/// 旅行者の現在地の座標が不変条件を満たさなかった理由。
#[derive(Debug, Clone, Copy, PartialEq, thiserror::Error)]
pub enum 旅行者の現在地の生成の失敗 {
    #[error("座標(東{東:?}, 北{北:?})が有限な数値でない(NaN または無限大。旅行者の現在地の座標は有限な数値でなければならない)")]
    座標が有限な数値でない { 東: メートル, 北: メートル },
}

/// 歩行の規則の速さが不変条件を満たさなかった理由。
#[derive(Debug, Clone, Copy, PartialEq, thiserror::Error)]
pub enum 歩行の規則の生成の失敗 {
    #[error("速さ{速さ:?}が有限な0以上の数値でない(歩行の規則の速さは有限かつ0以上でなければならない)")]
    速さが有限な0以上の数値でない { 速さ: メートル毎秒 },
}
