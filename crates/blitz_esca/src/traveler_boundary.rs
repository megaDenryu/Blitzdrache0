//! 旅行者が移動可能な世界の境界定義(Issue #137)。
//!
//! 世界のルールとして旅行者の行動を律する空間的制約と判定結果を定義する。移動可能範囲は各軸の最小が最大以下で
//! あることを不変条件に持ち、公開フィールドの指定DTOを検証して初めて得られる。

use blitz_design::M不変データ;
use blitz_math::メートル;

use crate::traveler::旅行者の現在地;
use crate::traveler_boundary_error::{移動可能範囲の生成の失敗, 移動可能範囲の軸};

/// 境界による座標制限の計算結果DTO。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 境界制限結果 {
    pub 制限後の東: メートル,
    pub 制限後の北: メートル,
    pub 衝突した: bool,
}

impl M不変データ for 境界制限結果 {}

/// 移動可能範囲を作るための指定。検証を通ると移動可能範囲になる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 移動可能範囲の指定 {
    pub 東の最小: メートル,
    pub 東の最大: メートル,
    pub 北の最小: メートル,
    pub 北の最大: メートル,
}

impl M不変データ for 移動可能範囲の指定 {}

impl 移動可能範囲の指定 {
    /// 各軸の最小が最大以下であり、どの端も有限な数値であることを確かめて移動可能範囲を作る。
    pub fn 検証する(self) -> Result<移動可能範囲, 移動可能範囲の生成の失敗> {
        Ok(移動可能範囲 {
            東: 軸の範囲::検証する(移動可能範囲の軸::東西, self.東の最小, self.東の最大)?,
            北: 軸の範囲::検証する(移動可能範囲の軸::南北, self.北の最小, self.北の最大)?,
        })
    }
}

/// 旅行者が歩行可能な空間の東西南北の限界範囲。各軸の最小が最大以下であることを保つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 移動可能範囲 {
    東: 軸の範囲,
    北: 軸の範囲,
}

impl M不変データ for 移動可能範囲 {}

impl 移動可能範囲 {
    /// 目的地を境界内に収め、収めた位置と、境界に当たって位置が変わったかを返す。
    pub fn 制限する(&self, 目的地: 旅行者の現在地) -> 境界制限結果 {
        let 制限後の東 = self.東.収める(目的地.東());
        let 制限後の北 = self.北.収める(目的地.北());
        境界制限結果 {
            制限後の東,
            制限後の北,
            衝突した: 制限後の東 != 目的地.東() || 制限後の北 != 目的地.北(),
        }
    }
}

// 1つの軸の最小と最大。最小が最大以下であることを検証して作る。
#[derive(Debug, Clone, Copy, PartialEq)]
struct 軸の範囲 {
    最小: メートル,
    最大: メートル,
}

impl 軸の範囲 {
    fn 検証する(軸: 移動可能範囲の軸, 最小: メートル, 最大: メートル) -> Result<Self, 移動可能範囲の生成の失敗> {
        if !最小.値().is_finite() || !最大.値().is_finite() {
            return Err(移動可能範囲の生成の失敗::数値でない { 軸 });
        }
        if 最小 > 最大 {
            return Err(移動可能範囲の生成の失敗::最小が最大を超えている { 軸, 最小, 最大 });
        }
        Ok(Self { 最小, 最大 })
    }

    fn 収める(&self, 値: メートル) -> メートル {
        if 値 < self.最小 {
            self.最小
        } else if 値 > self.最大 {
            self.最大
        } else {
            値
        }
    }
}
