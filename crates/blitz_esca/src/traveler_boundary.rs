//! 旅行者が移動可能な世界の境界定義(Issue #137)。
//!
//! 世界のルールとして旅行者の行動を律する移動可能限界を定義する。

use blitz_math::メートル;
use crate::ontology::MDTO;

/// 旅行者が歩行可能な空間の東西南北の限界範囲DTO。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 移動可能範囲 {
    pub 東の最小: メートル,
    pub 東の最大: メートル,
    pub 北の最小: メートル,
    pub 北の最大: メートル,
}

impl MDTO for 移動可能範囲 {}

impl 移動可能範囲 {
    /// 事実上無制限の広大な空間境界を生成する。
    pub fn 無制限() -> Self {
        Self {
            東の最小: メートル::生成する(-100_000.0),
            東の最大: メートル::生成する(100_000.0),
            北の最小: メートル::生成する(-100_000.0),
            北の最大: メートル::生成する(100_000.0),
        }
    }

    /// 指定した座標を境界内に収め、壁に衝突したかの判定結果を返す。
    pub fn 制限する(&self, 東: f32, 北: f32) -> (f32, f32, bool) {
        let 制限東 = 東.clamp(self.東の最小.値(), self.東の最大.値());
        let 制限北 = 北.clamp(self.北の最小.値(), self.北の最大.値());
        let 衝突 = (制限東 - 東).abs() > 1e-6 || (制限北 - 北).abs() > 1e-6;
        (制限東, 制限北, 衝突)
    }
}
