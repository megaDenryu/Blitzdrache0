//! 旅行者の歩行の規則と描画位置(判断: Esca設計正本)。
//!
//! 歩行の状態遷移そのもの(M状態遷移関数)と描画位置の射影(M射影関数)は、状態の型と同じファイル(`居場所.rs`)に置く。
//! ここは状態遷移へ読み取り専用で与える規則と、射影が返す描画用のDTOを持つ。
//! 規則は身体の運動法則(`歩行の規則`)と空間制約(`区域の空間制約`。地図の区域と、どの通り口が通れるかを決める経路の開閉の状態)を直交させて合成する(設計正本 4.4 条2)。
//! 空間制約が持つ開閉の状態は別の仕組み(経路の開閉)の状態から作った読み取り専用の値であり、規則の一部として渡してよい(設計オントロジー 3.5.2。2026-09-26 オーナー裁定)。
//! 空間制約の地図は `M共有される不変データ` であり `Arc` で共有するため、経路の開閉と旅行者の歩行の状態遷移がこの規則を刻みごとに組んでも、地図は複製されない。
//! 開閉の状態はその状態遷移から値で移され、歩行の後に `開閉の状態を取り出す` で状態遷移へ返る。

use blitz_design::{M不変データ, M規則};
use blitz_math::メートル;

use crate::地点と経路::空間制約::区域の空間制約;
use crate::地点と経路::開閉の状態::経路の開閉の状態;
use crate::旅行者::歩行の規則;

/// 歩行状態遷移を律する身体規則と空間制約の統合規則(M規則)。
#[derive(Clone)]
pub struct 歩行の状態遷移の規則 {
    身体: 歩行の規則,
    空間制約: 区域の空間制約,
}

impl M不変データ for 歩行の状態遷移の規則 {}
impl M規則 for 歩行の状態遷移の規則 {}

impl 歩行の状態遷移の規則 {
    pub fn 生成する(身体: 歩行の規則, 空間制約: 区域の空間制約) -> Self {
        Self { 身体, 空間制約 }
    }

    pub fn 身体(&self) -> &歩行の規則 {
        &self.身体
    }

    pub fn 空間制約(&self) -> &区域の空間制約 {
        &self.空間制約
    }

    /// 規則を解き、空間制約が受け取った開閉の状態を返す。経路の開閉と旅行者の歩行の状態遷移が、歩行の後に開閉の状態を複製せずに次の状態へ戻すための口である。
    pub fn 開閉の状態を取り出す(self) -> 経路の開閉の状態 {
        self.空間制約.開閉の状態を取り出す()
    }
}

/// 描画エンジンに渡すための純粋な位置DTO。単位はGPU境界まで保つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 旅行者の描画位置 {
    東メートル: メートル,
    北メートル: メートル,
}

impl M不変データ for 旅行者の描画位置 {}

impl 旅行者の描画位置 {
    pub fn 生成する(東メートル: メートル, 北メートル: メートル) -> Self {
        Self { 東メートル, 北メートル }
    }

    pub fn 東メートル(&self) -> メートル {
        self.東メートル
    }

    pub fn 北メートル(&self) -> メートル {
        self.北メートル
    }
}
