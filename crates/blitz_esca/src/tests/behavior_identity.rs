//! 旅行者の現在地の状態の同一性(PR #177 のBlocker 2の是正と、Blocker Bの是正)。
//!
//! 名指し(`behavior_naming`)から分けるのは、名指しが命題が名指す先であり、同一性が探索の済みの判断だからである。
//! この2つは別の口であり続けるが、**源は同じビットの並びである**。名指しだけを位置のマスへ丸めると、
//! 探索が別物として残した2つの現在地が、命題の層では同じ1件として引き当てられる。
//! 丸めない写しをここへ置き、名指しがこの写しを読むことでその取り違えを断つ。
//!
//! 人が読む粗い表記は `behavior_display` が別に持つ。

use super::behavior_bits::単精度のビットの並び;
use crate::traveler::旅行者の現在地;

/// 現在地のビット表現とは、旅行者の現在地の東と北を単精度のビットの並びのまま写した、状態の同一性のことである。
/// 丸めないため、異なる現在地が同じ表現へ写ることは無い。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct 現在地のビット表現 {
    東: 単精度のビットの並び,
    北: 単精度のビットの並び,
}

impl 現在地のビット表現 {
    /// 現在地をビットの並びへ写す。
    pub fn 現在地から写す(現在地: &旅行者の現在地) -> Self {
        Self {
            東: 単精度のビットの並び::値から写す(現在地.東().値()),
            北: 単精度のビットの並び::値から写す(現在地.北().値()),
        }
    }

    /// 人が読む1行の表記。名指しがこの表記を名前に入れるため、異なる現在地が同じ名前へ写ることは無い。
    pub fn 表記(&self) -> String {
        format!("東{}, 北{}", self.東.表記(), self.北.表記())
    }
}
