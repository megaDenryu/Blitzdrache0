//! 旅行者の現在地の状態の同一性(PR #177 のBlocker 2の是正)。
//!
//! 名指し(`behavior_naming`)から分けるのは、名指しが人が読む表示と命題が名指す先であり、同一性が探索の済みの判断だからである。
//! 名指しは位置をマスの番号へ丸めるため、別の現在地が同じ名前を持ちうる。その名前を同一性に使うと、探索が別の現在地を
//! 同じ1件として捨て、辿らなかった状態を残したまま全件を名乗る。丸めない写しをここへ置くことでその取り違えを断つ。

use blitz_math::メートル;

use crate::traveler::旅行者の現在地;

/// 現在地のビット表現とは、旅行者の現在地の東と北を単精度のビットの並びのまま写した、状態の同一性のことである。
/// 単精度は `Eq` も `Hash` も持たないため、ビットの並びへ写して同一性の鍵にする。丸めないため、異なる現在地が同じ表現へ写ることは無い。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct 現在地のビット表現 {
    東のビット: u32,
    北のビット: u32,
}

impl 現在地のビット表現 {
    /// 現在地をビットの並びへ写す。
    pub fn 現在地から写す(現在地: &旅行者の現在地) -> Self {
        Self {
            東のビット: ビットへ写す(現在地.東()),
            北のビット: ビットへ写す(現在地.北()),
        }
    }
}

// 長さをビットの並びへ写す。旅行者の現在地は生成の口が有限であることを確かめているため、ここへ数値でない値は来ない。
fn ビットへ写す(長さ: メートル) -> u32 {
    長さ.値().to_bits()
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod 現在地のビット表現の試験 {
    use super::現在地のビット表現;
    use crate::tests::behavior_naming::現在地を名指すマスの一辺;
    use crate::traveler::旅行者の現在地;
    use blitz_math::メートル;

    fn 現在地(東: f32, 北: f32) -> 旅行者の現在地 {
        旅行者の現在地::生成する(メートル::生成する(東), メートル::生成する(北)).unwrap()
    }

    #[test]
    fn 同じマスへ丸められる2つの現在地は名前が同じでも同一性が別である() {
        let 一辺 = 現在地を名指すマスの一辺::一メートル();
        let 左 = 現在地(5.0, 5.0);
        let 右 = 現在地(5.2, 5.0);
        assert_eq!(一辺.現在地を名指す(&左), 一辺.現在地を名指す(&右), "同じマスへ丸められる2つの現在地の名前が違う");
        assert_ne!(現在地のビット表現::現在地から写す(&左), 現在地のビット表現::現在地から写す(&右), "名前が同じ2つの現在地の同一性まで同じになっている");
    }
}
