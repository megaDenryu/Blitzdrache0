//! 区域が1つだけの地図の試料(Issue #187 の作業G2)。第1段階の歩行の試験を、長方形の移動可能範囲でなく1つの区域で表すためと、斜めの壁を持つ区域の上で歩く試験に使う。
//!
//! 地図は広場という地点を1つだけ持ち、経路を持たない。広場の区域は東と北の最小と最大で決まる長方形であり、頂点を南西の角から反時計回りに並べる。
//! 経路が無いため、広場の境目はどこも閉じた境目であり、歩行は境目で滑るか止まる(第1段階の移動可能範囲の端と同じ振る舞い)。

#![allow(clippy::expect_used)]

use blitz_math::{メートル, 秒};

use crate::elapsed_time::経過時間;
use crate::transition_parameter::遷移パラメータ;
use crate::traveler::{旅行者の現在地, 歩行の規則};
use crate::traveler_movement::歩行遷移の規則;
use crate::地点と経路::地点と経路の図式::地点Id;
use crate::地点と経路::{区域, 区域の指定, 区域の空間制約, 区域の頂点, 地点, 地点と経路のグラフ, 地点と経路の図式, 経路の開閉の規則};
use crate::居場所::旅行者の居場所;
use crate::時刻::世界の時刻;

/// 長方形の東と北の最小と最大。
pub struct 長方形の端 {
    pub 東の最小: f32,
    pub 東の最大: f32,
    pub 北の最小: f32,
    pub 北の最大: f32,
}

impl 長方形の端 {
    /// 南西の角から反時計回りに4つの頂点を並べた区域。
    pub fn 区域にする(&self) -> 区域 {
        let 角一覧 = [(self.東の最小, self.北の最小), (self.東の最大, self.北の最小), (self.東の最大, self.北の最大), (self.東の最小, self.北の最大)];
        一つの区域の広場::頂点から作る(&角一覧).区域
    }

    /// この長方形を区域に持つ広場だけの地図と、与えた身体の規則を持つ歩行の規則。
    pub fn 歩行の規則を組む(&self, 身体: 歩行の規則) -> 歩行遷移の規則 {
        一つの区域の広場 { 区域: self.区域にする() }.歩行の規則を組む(身体)
    }

    /// この長方形を区域に持つ広場にいる、その現在地の居場所。
    pub fn 広場の居場所(&self, 現在地: 旅行者の現在地) -> 旅行者の居場所 {
        一つの区域の広場 { 区域: self.区域にする() }.広場の居場所(現在地)
    }
}

/// 区域を1つだけ持つ広場。長方形でない区域(斜めの壁を持つ区域)の上で歩く試験が使う。
pub struct 一つの区域の広場 {
    pub 区域: 区域,
}

impl 一つの区域の広場 {
    /// 北を上に見て反時計回りに並べた頂点の東と北から、広場の区域を作る。
    pub fn 頂点から作る(頂点一覧: &[(f32, f32)]) -> Self {
        let 頂点一覧 = 頂点一覧
            .iter()
            .map(|(東, 北)| 区域の頂点 {
                東: メートル::生成する(*東),
                北: メートル::生成する(*北),
            })
            .collect();
        Self {
            区域: 区域の指定 { 頂点一覧 }.検証する().expect("反時計回りの単純多角形の頂点は区域になるべきである"),
        }
    }

    /// この区域を持つ広場だけの地図。
    pub fn 広場だけの地図を組む(&self) -> 地点と経路のグラフ {
        #[rustfmt::skip]
        let つながり = graphite::graph!(地点と経路の図式 {
            広場 = 地点::区域で生成する(self.区域.clone()),
        })
        .expect("多重度の制約を持たない図式の地図は組めるべきである");
        地点と経路のグラフ::検証して生成する(つながり.into_graph()).expect("区域が1つの地図は検証を通るべきである")
    }

    /// 広場だけの地図と、与えた身体の規則を持つ歩行の規則。経路が無いため、通れる通り口は空である。
    pub fn 歩行の規則を組む(&self, 身体: 歩行の規則) -> 歩行遷移の規則 {
        let 地図 = self.広場だけの地図を組む();
        let 開閉の状態 = 経路の開閉の規則::生成する(地図.clone()).はじめの状態();
        歩行遷移の規則::生成する(身体, 区域の空間制約::開閉の状態から導く(地図, &開閉の状態).expect("地図の規則のはじめの状態から空間制約を導けるべきである"))
    }

    /// 広場にいる、その現在地の居場所。
    pub fn 広場の居場所(&self, 現在地: 旅行者の現在地) -> 旅行者の居場所 {
        let 広場 = self.広場だけの地図を組む().地点を確かめる(&地点Id("広場".to_string())).expect("広場は地図に在る");
        旅行者の居場所::生成する(広場, 現在地)
    }
}

/// 東と北から作る現在地。
pub fn 現在地(東: f32, 北: f32) -> 旅行者の現在地 {
    旅行者の現在地::生成する(メートル::生成する(東), メートル::生成する(北)).expect("有限な座標は現在地になるべきである")
}

/// 世界の始まりから、与えた秒数だけ進む遷移パラメータ。
pub fn 経過(秒数: f32) -> 遷移パラメータ {
    遷移パラメータ::最初の刻みを生成する(世界の時刻::世界の始まり(), 経過時間::生成する(秒::生成する(秒数)).expect("有限な0以上の秒数は経過時間になるべきである"))
}
