//! 時刻の予定と出来事(開閉の命令)が同じ経路にぶつかったとき出来事が勝つこと(2026-09-26 オーナー裁定)を固定する試験(Issue #187 の作業G1)。
//!
//! 出来事が一度でも閉じたり開けたりした経路には、それ以降、時刻の予定が当たらない。その経路の開閉を変えられるのは別の出来事だけである。
//! 時刻の予定は、出来事が一度も触れていない経路にだけ当たる。固定する例は3つである。(a) 峠道の予定の前に崖崩れで閉じた峠道は、予定の終わりの時刻を過ぎても閉じたまま残る。
//! (b) 夜のあいだ閉じる城門を夜中に命令で開けると、朝の予定も次の夜の予定も効かず開いたまま残る。時(30時は翌朝の6時、44時は次の夜の20時)は世界の始まりを0時として数える。(c) 出来事が触れていない経路には、予定がこれまでどおり当たる。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::expect_used)]

use super::地点と経路の試料::{
    刻み, 区域の一辺, 封鎖できる経路を指す, 峠道が閉じる秒, 峠道が開く秒, 時刻, 東の真ん中の辺, 正方形の区域, 西の真ん中の辺, 試験の地図を組む, 試験の規則を組む, 通り口
};
use crate::地点と経路::{
    地点, 地点と経路のグラフ, 地点と経路の図式, 経路の種類, 経路の積み荷, 経路の開閉, 経路の開閉の予定, 経路の開閉の出来事, 経路の開閉の命令, 経路の開閉の状態, 経路の開閉の規則, 閉じている時間帯の指定
};

const 一時間の秒: f64 = 3_600.0;

fn 進める(状態: 経路の開閉の状態, 命令: 経路の開閉の命令, 規則: &経路の開閉の規則, 始まりの秒: f64) -> (経路の開閉の状態, Vec<経路の開閉の出来事>) {
    let 成功 = 状態.開閉を遷移する(&命令, 規則, 刻み(始まりの秒, 1.0)).expect("地図に在る経路の遷移は成功するべきである");
    (成功.次の状態, 成功.出来事一覧)
}

// 20時から翌6時まで閉じる予定を2晩ぶん持つ城門1本の地図。世界の時刻は世界の始まりを0時とする。
fn 城門の地図を組む() -> 地点と経路のグラフ {
    let 夜 = |始まりの時: f64| {
        閉じている時間帯の指定 {
            始まり: 時刻(始まりの時 * 一時間の秒),
            終わり: 時刻((始まりの時 + 10.0) * 一時間の秒),
        }
        .検証する()
        .expect("始まりが終わりより前の時間帯は検証を通るべきである")
    };
    let 予定 = 経路の開閉の予定::生成する(経路の開閉::開いている, vec![夜(20.0), 夜(44.0)]).expect("重ならない2晩の予定は検証を通るべきである");
    #[rustfmt::skip]
    let つながり = graphite::graph!(地点と経路の図式 {
        城下町 = 地点::区域で生成する(正方形の区域(0.0, 0.0)),
        郊外 = 地点::区域で生成する(正方形の区域(区域の一辺, 0.0)),
        城門 = 経路(城下町 -[経路の積み荷::生成する(経路の種類::門, 通り口(東の真ん中の辺, 西の真ん中の辺), 予定)]- 郊外),
    })
    .expect("多重度の制約を持たない図式の地図は組めるべきである");
    地点と経路のグラフ::検証して生成する(つながり.into_graph()).expect("区域と通り口の不変条件を満たす地図は検証を通るべきである")
}

#[test]
fn 例a_予定の前に崖崩れで閉じた峠道は予定の終わりを過ぎても閉じたまま残る() {
    let 規則 = 試験の規則を組む();
    let 峠道 = 封鎖できる経路を指す(&試験の地図を組む(), "峠道");
    let (状態, 出来事一覧) = 進める(規則.はじめの状態(), 経路の開閉の命令::経路を閉じる { 経路: 峠道.clone() }, &規則, 5.0);
    assert_eq!(出来事一覧, vec![経路の開閉の出来事::経路が閉じた { 経路: 峠道.clone() }]);
    let (状態, 出来事一覧) = 進める(状態, 経路の開閉の命令::命令が無い, &規則, 峠道が閉じる秒);
    assert!(出来事一覧.is_empty(), "出来事が閉じた峠道に予定の始まりが当たった: {出来事一覧:?}");
    let (状態, 出来事一覧) = 進める(状態, 経路の開閉の命令::命令が無い, &規則, 峠道が開く秒);
    assert!(出来事一覧.is_empty(), "出来事が閉じた峠道に予定の終わりが当たった: {出来事一覧:?}");
    assert_eq!(状態.経路の開閉(&峠道), 経路の開閉::閉じている, "崖崩れで閉じた峠道が予定の終わりで開いた");
}

#[test]
fn 例b_夜中に命令で開けた城門は朝の予定も次の夜の予定も効かず開いたまま残る() {
    let 地図 = 城門の地図を組む();
    let 城門 = 封鎖できる経路を指す(&地図, "城門");
    let 規則 = 経路の開閉の規則::生成する(地図);
    let (状態, 出来事一覧) = 進める(規則.はじめの状態(), 経路の開閉の命令::命令が無い, &規則, 20.0 * 一時間の秒);
    assert_eq!(出来事一覧, vec![経路の開閉の出来事::経路が閉じた { 経路: 城門.clone() }], "20時の予定で城門が閉じていない");
    let (mut 状態, 出来事一覧) = 進める(状態, 経路の開閉の命令::経路を開く { 経路: 城門.clone() }, &規則, 22.0 * 一時間の秒);
    assert_eq!(出来事一覧, vec![経路の開閉の出来事::経路が開いた { 経路: 城門.clone() }]);
    for 時 in [30.0, 44.0, 54.0] {
        let (次の状態, 出来事一覧) = 進める(状態, 経路の開閉の命令::命令が無い, &規則, 時 * 一時間の秒);
        assert!(出来事一覧.is_empty(), "命令で開けた城門に{時}時の予定が当たった: {出来事一覧:?}");
        assert_eq!(次の状態.経路の開閉(&城門), 経路の開閉::開いている);
        状態 = 次の状態;
    }
}

#[test]
fn 例c_出来事が触れていない経路には予定がこれまでどおり当たる() {
    let 規則 = 試験の規則を組む();
    let 地図 = 試験の地図を組む();
    let (峠道, 橋) = (封鎖できる経路を指す(&地図, "峠道"), 封鎖できる経路を指す(&地図, "橋"));
    let (状態, 出来事一覧) = 進める(規則.はじめの状態(), 経路の開閉の命令::経路を閉じる { 経路: 橋.clone() }, &規則, 峠道が閉じる秒);
    assert_eq!(出来事一覧, vec![経路の開閉の出来事::経路が閉じた { 経路: 峠道.clone() }, 経路の開閉の出来事::経路が閉じた { 経路: 橋.clone() }]);
    assert_eq!(状態.出来事が触れた経路一覧().cloned().collect::<Vec<_>>(), vec![橋], "出来事が触れた経路に命令の経路だけが入っていない");
    let (状態, 出来事一覧) = 進める(状態, 経路の開閉の命令::命令が無い, &規則, 峠道が開く秒);
    assert_eq!(出来事一覧, vec![経路の開閉の出来事::経路が開いた { 経路: 峠道.clone() }]);
    assert_eq!(状態.経路の開閉(&峠道), 経路の開閉::開いている);
}
