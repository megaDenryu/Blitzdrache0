// 閉じている経路の名前を並べた開閉の状態と、その速さの身体から組む歩行の規則。
fn 歩行の規則(閉じている経路の名前一覧: &[&str], 速さ: f32) -> 歩行遷移の規則 {
    let 地図 = 試験の地図を組む();
    let 指定 = 経路の開閉の状態の指定 {
        閉じている経路: 閉じている経路の名前一覧.iter().map(|名前| 封鎖できる経路を指す(&地図, 名前)).collect(),
        出来事が触れた経路: Vec::new(),
    };
    let 開閉の状態: 経路の開閉の状態 = 試験の規則を組む().指定を地図で確かめて状態を作る(指定).expect("地図の経路だけの指定は状態になるべきである");
    let 身体 = 歩行の規則::生成する(メートル毎秒::生成する(速さ)).expect("有限な0以上の速さは規則になるべきである");
    歩行遷移の規則::生成する(身体, 区域の空間制約::開閉の状態から導く(地図, &開閉の状態))
}

fn 居場所(地点の名前: &str, 東: f32, 北: f32) -> 旅行者の居場所 {
    let 地点 = 試験の地図を組む().地点を確かめる(&地点Id(地点の名前.to_string())).expect("試験の地図の地点");
    旅行者の居場所::生成する(地点, 現在地(東, 北))
}

fn 歩く(居場所: 旅行者の居場所, 方向: 歩行方向, 規則: &歩行遷移の規則) -> 遷移成功結果<旅行者の居場所, 旅行者の出来事> {
    居場所.歩行を遷移する(&旅行者の意図::歩く { 方向 }, 規則, 経過(1.0)).expect("区域の中の遷移は成功するべきである")
}

fn 斜め(入力: キーボード歩行入力) -> 歩行方向 {
    歩行方向::キー入力から導く(&入力).expect("斜めのキー入力は向きになる")
}

// 現在地が期待の点から1ミリメートル以内にあるか。斜めの向きの単精度の丸めで、期待の点からわずかにずれるため。
fn 近いか(現在地: 旅行者の現在地, 東: f32, 北: f32) -> bool {
    (現在地.東() - メートル::生成する(東)).値().abs() < 1.0e-3 && (現在地.北() - メートル::生成する(北)).値().abs() < 1.0e-3
}

#[test]
fn 反例1_閉じた門の辺では境目に沿って滑り来た区域に残る() {
    // 峠の(14.5, 9)から北東へ3メートル歩く。関所(北の境目の14から16メートル)は閉じているため、境目に当たって東へ滑る。
    let 結果 = 歩く(居場所("峠", 14.5, 9.0), 斜め(キーボード歩行入力 { 上: true, 右: true, ..Default::default() }), &歩行の規則(&["関所"], 3.0));
    assert_eq!(結果.次の状態.地点().表記(), "峠");
    assert!(近いか(結果.次の状態.現在地(), 14.5 + 3.0 * std::f32::consts::FRAC_1_SQRT_2, 10.0), "{:?}", 結果.次の状態.現在地());
    assert_eq!(結果.出来事一覧, vec![旅行者の出来事::障害物に遮られた]);
}

#[test]
fn 反例1_開いた門の辺では隣の区域へ入る() {
    let 結果 = 歩く(居場所("峠", 15.0, 8.0), 歩行方向::北(), &歩行の規則(&[], 3.0));
    assert_eq!(結果.次の状態, 居場所("城下町", 15.0, 11.0));
    assert!(結果.出来事一覧.is_empty());
    let 閉じた門 = 歩く(居場所("峠", 15.0, 8.0), 歩行方向::北(), &歩行の規則(&["関所"], 3.0));
    assert_eq!(閉じた門.次の状態, 居場所("峠", 15.0, 10.0));
    assert_eq!(閉じた門.出来事一覧, vec![旅行者の出来事::障害物に遮られた]);
}

#[test]
fn 反例2_1刻みで開いた通り口を2つ続けて抜ける() {
    // 城下町の(12, 17)から南西へ9√2メートル歩くと、(10, 15)で橋を、(5, 10)で渡しを抜け、村の(3, 8)に着く。
    let 規則 = 歩行の規則(&[], 9.0 * std::f32::consts::SQRT_2);
    let 結果 = 歩く(居場所("城下町", 12.0, 17.0), 斜め(キーボード歩行入力 { 下: true, 左: true, ..Default::default() }), &規則);
    assert_eq!(結果.次の状態.地点().表記(), "村");
    assert!(近いか(結果.次の状態.現在地(), 3.0, 8.0), "{:?}", 結果.次の状態.現在地());
    assert!(結果.出来事一覧.is_empty());
}

#[test]
fn 反例2_2本目の境目が閉じていればそこで止まる() {
    // 村の(8, 5)から東へ15メートル歩くと、峠道を抜けて峠へ入り、峠の東の端(外周の閉じた境目)で止まる。
    let 結果 = 歩く(居場所("村", 8.0, 5.0), 歩行方向::東(), &歩行の規則(&[], 15.0));
    assert_eq!(結果.次の状態, 居場所("峠", 20.0, 5.0));
    assert_eq!(結果.出来事一覧, vec![旅行者の出来事::障害物に遮られた]);
}

#[test]
fn 反例3_区域の角へ斜めに歩くと角で止まる() {
    let 結果 = 歩く(居場所("村", 1.0, 1.0), 斜め(キーボード歩行入力 { 下: true, 左: true, ..Default::default() }), &歩行の規則(&[], 3.0));
    assert_eq!(結果.次の状態.地点().表記(), "村");
    assert!(近いか(結果.次の状態.現在地(), 0.0, 0.0), "{:?}", 結果.次の状態.現在地());
    assert_eq!(結果.出来事一覧, vec![旅行者の出来事::障害物に遮られた]);
}

#[test]
fn 反例4_通り口の上で止まった旅行者は来た区域にいて次の刻みは門の開閉で決まる() {
    let 門の上 = 居場所("村", 10.0, 5.0);
    let 閉じた = 歩く(門の上.clone(), 歩行方向::東(), &歩行の規則(&["峠道"], 3.0));
    assert_eq!(閉じた.次の状態, 門の上, "閉じた峠道の上から向こうへは進めない");
    assert_eq!(閉じた.出来事一覧, vec![旅行者の出来事::障害物に遮られた]);
    assert_eq!(歩く(門の上.clone(), 歩行方向::東(), &歩行の規則(&[], 3.0)).次の状態, 居場所("峠", 13.0, 5.0));
    assert_eq!(歩く(門の上, 歩行方向::西(), &歩行の規則(&["峠道"], 3.0)).次の状態, 居場所("村", 7.0, 5.0));
}

#[test]
fn 点を含む地点は区域の中なら1つに決まり世界の外と境目の上では決まらない() {
    let 空間制約 = 歩行の規則(&[], 3.0).空間制約().clone();
    let 点 = |東: f32, 北: f32| 現在地(東, 北).平面の点へ広げる();
    assert_eq!(空間制約.点を含む地点を決める(&点(5.0, 5.0)).expect("村の中の点").表記(), "村");
    assert_eq!(空間制約.点を含む地点を決める(&点(25.0, 5.0)), Err(地点を決められない理由::世界の外にある));
    assert!(matches!(空間制約.点を含む地点を決める(&点(10.0, 8.0)), Err(地点を決められない理由::区域の境目の上にある { .. })), "村と峠の境目の上の点");
}
