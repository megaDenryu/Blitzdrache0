//! 区域をまたぐ歩行の反例を固定する試験(Issue #187 の作業G2)。試験の地図(`地点と経路の試料.rs`)の上で歩く。
//!
//! 固定する反例は4つである。(1) 閉じた門の辺では境目に沿って滑り、開いた門の辺では隣の区域へ入る。
//! (2) 1刻みで境目を2本越える移動は、開いた通り口を2つ続けて抜け、2本目が閉じた境目ならそこで止まる。
//! (3) 区域の角へ斜めに歩くと角で止まる。(4) 境目(通り口)の上で止まった旅行者の次の刻みは、来た側の区域から判断される。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::expect_used)]

