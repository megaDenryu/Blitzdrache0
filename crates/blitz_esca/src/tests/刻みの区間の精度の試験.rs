//! 刻みの区間が、世界が始まってから長い時間が経った時刻でも空にならないことと、次の刻みの始まりが前の刻みの終わりと隙間なく続くことを固定する試験(Issue #187 の作業G1)。
//!
//! 世界の時刻を単精度の秒で持つと、約2^19秒(約6日)から先で表現の刻みが1/32秒を超え、始まりの時刻に1/60秒を足しても始まりの時刻のままになる。
//! すると刻みの区間が空になり、その刻みに来るはずの時刻の予定が来なくなる。題材の時刻は、単精度ならこの欠陥が起きる大きさを選ぶ。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::expect_used)]

use blitz_math::秒;

use super::地点と経路の試料::{刻み, 時刻};
use crate::elapsed_time::経過時間;

const 基本刻みの秒: f32 = 1.0 / 60.0; // ゲームの固定刻みの長さ
const 約6日を超えた秒: f64 = 1_000_000.0; // 約11.6日。単精度の表現の刻みが0.0625秒になる大きさ
const 約34年の秒: f64 = 1_073_741_824.0; // 2の30乗秒

#[test]
fn 題材の時刻は単精度なら六十分の一秒を足しても変わらない大きさである() {
    // 下の試験が空虚に通らないこと(題材の時刻が、単精度で持てば刻みの区間が空になる大きさであること)を確かめる。
    assert_eq!(1_000_000.0_f32 + 基本刻みの秒, 1_000_000.0_f32);
}

#[test]
fn 約6日を超えた時刻でも六十分の一秒の刻みは始まりの時刻を覆い区間が空にならない() {
    for 始まり in [約6日を超えた秒, 約34年の秒] {
        let 刻み = 刻み(始まり, 基本刻みの秒);
        assert!(刻み.その時刻がこの刻みに来るか(時刻(始まり)), "始まりが{始まり}秒の刻みの区間が空になっている");
        assert!(!刻み.その時刻がこの刻みに来るか(時刻(始まり + 1.0)), "始まりが{始まり}秒の刻みが1秒後の時刻まで覆っている");
    }
}

#[test]
fn 次の刻みの始まりは前の刻みの終わりと隙間なく続き予定の時刻はちょうど1つの刻みに来る() {
    let 一刻み = 経過時間::生成する(秒::生成する(基本刻みの秒)).expect("1/60秒は経過時間になるべきである");
    let 予定の時刻 = 時刻(約6日を超えた秒 + 1.0);
    let mut いまの刻み = 刻み(約6日を超えた秒, 基本刻みの秒);
    let mut 来た回数 = 0;
    for _ in 0..120 {
        来た回数 += usize::from(いまの刻み.その時刻がこの刻みに来るか(予定の時刻));
        let 次の刻み = いまの刻み.次の刻みへ進める(一刻み).expect("有限な時刻から進めた刻みは世界の時刻になるべきである");
        assert!(次の刻み.刻みの始まりの時刻() > いまの刻み.刻みの始まりの時刻(), "次の刻みの始まりが前の刻みの始まりから進んでいない");
        いまの刻み = 次の刻み;
    }
    assert_eq!(来た回数, 1, "120刻み(2秒)の間に、1秒後の予定の時刻がちょうど1つの刻みに来ていない");
}
