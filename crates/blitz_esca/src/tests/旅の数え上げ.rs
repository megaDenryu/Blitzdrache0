//! 経路の開閉と旅行者の歩行の更新(経路の開閉と旅行者の歩行を合わせた遷移)を、小さな地図の全状態で数え上げる、有限に数え上げられる領域(Issue #187 の作業G2)。
//!
//! 地図と状態・コマンド・出来事の型は `旅の数え上げの試料.rs` が持つ。
//! 旅行者は村の(5, 5)から始まり、1刻みに5メートル歩く。どの通り口も境目の真ん中(5メートルの位置)にあり、区域の端も5メートルの倍数にあるため、
//! 現在地はいつも5メートルの格子の上にあり、状態は有限である。コマンドは、開閉の命令と旅行者の意図の組である。
//! 開閉の命令は命令が無いと峠道を閉じる・開くの3つであり、関所を開ける命令を入れるかは領域を組むときに選ぶ(入れない領域では城下町へ入れないことを確かめる)。
//! どちらの数え上げも取りうる値を全部並べるため、網羅性は全件を数え上げたで返る。
//!
//! `一回遷移する` は `経路の開閉と旅行者の歩行の進行::経路の開閉と旅行者の歩行を1回更新する` をそのまま呼び、1刻みの順序と2つの遷移の意味を試験の側へ書き写さない(Issue #173 が禁じた形)。

#![allow(clippy::expect_used)]

use blitz_design_verification::{数え上げ, 有限に数え上げられる領域, 設計概念への参照, 遷移の帰結};
use blitz_math::メートル毎秒;

use super::一つの区域の試料::現在地;
use super::地点と経路の試料::{刻み, 封鎖できる経路を指す};
use super::旅の数え上げの試料::{城下町の地図を組む, 旅のコマンド, 旅の出来事, 旅の名前の空間, 旅の状態, 旅の状態の同一性, 旅の状態の表記};
use crate::traveler::{旅行者の意図, 歩行の規則};
use crate::walking_direction::歩行方向;
use crate::地点と経路::地点と経路の図式::地点Id;
use crate::地点と経路::{経路の開閉の命令, 経路の開閉の規則};
use crate::居場所::旅行者の居場所;
use crate::経路の開閉と旅行者の歩行::{経路の開閉と旅行者の歩行の更新への入力, 経路の開閉と旅行者の歩行の進行, 経路の開閉と旅行者の歩行の進行の指定};

/// 実物の `経路の開閉と旅行者の歩行の進行::経路の開閉と旅行者の歩行を1回更新する` を呼ぶ領域。
pub struct 旅を数え上げる領域 {
    開閉の規則: 経路の開閉の規則,
    身体: 歩行の規則,
    関所を開ける命令を入れるか: bool,
}

impl 旅を数え上げる領域 {
    /// 城下町の地図と、1刻みに5メートル歩く身体で領域を組む。関所を開ける命令をコマンドへ入れるかを選ぶ。
    pub fn 生成する(関所を開ける命令を入れるか: bool) -> Self {
        Self {
            開閉の規則: 経路の開閉の規則::生成する(城下町の地図を組む()),
            身体: 歩行の規則::生成する(メートル毎秒::生成する(5.0)).expect("有限な正の速さは規則になるべきである"),
            関所を開ける命令を入れるか,
        }
    }
}

impl 有限に数え上げられる領域 for 旅を数え上げる領域 {
    type 状態 = 旅の状態;
    type コマンド = 旅のコマンド;
    type 出来事 = 旅の出来事;
    type 状態の同一性 = 旅の状態の同一性;

    fn 初期状態を数え上げる(&self) -> 数え上げ<旅の状態> {
        let 村 = self.開閉の規則.地図().地点を確かめる(&地点Id("村".to_string())).expect("村は地図に在る");
        数え上げ::全件(vec![旅の状態 {
            開閉: self.開閉の規則.はじめの状態(),
            居場所: 旅行者の居場所::生成する(村, 現在地(5.0, 5.0)),
        }])
    }

    fn 状態で試すコマンドを数え上げる(&self, _状態: &旅の状態) -> 数え上げ<旅のコマンド> {
        let 峠道 = 封鎖できる経路を指す(self.開閉の規則.地図(), "峠道");
        let mut 命令一覧 = vec![経路の開閉の命令::命令が無い, 経路の開閉の命令::経路を閉じる { 経路: 峠道.clone() }, 経路の開閉の命令::経路を開く { 経路: 峠道 }];
        if self.関所を開ける命令を入れるか {
            命令一覧.push(経路の開閉の命令::経路を開く {
                経路: 封鎖できる経路を指す(self.開閉の規則.地図(), "関所"),
            });
        }
        let 意図一覧 = [
            旅行者の意図::静止,
            旅行者の意図::歩く { 方向: 歩行方向::東() },
            旅行者の意図::歩く { 方向: 歩行方向::西() },
            旅行者の意図::歩く { 方向: 歩行方向::北() },
            旅行者の意図::歩く { 方向: 歩行方向::南() },
        ];
        数え上げ::全件(命令一覧.iter().flat_map(|命令| 意図一覧.iter().map(|意図| 旅のコマンド::開閉と意図 { 命令: 命令.clone(), 意図: *意図 })).collect())
    }

    /// 実物の1刻みを呼ぶ。進行を始められないか、2つの遷移のどちらかが失敗したら、受け取った状態を失敗の元の状態として返す。
    fn 一回遷移する(&self, 状態: &旅の状態, コマンド: &旅のコマンド) -> 遷移の帰結<旅の状態, 旅の出来事> {
        let 旅のコマンド::開閉と意図 { 命令, 意図 } = コマンド;
        let 始めた = 経路の開閉と旅行者の歩行の進行::始める(経路の開閉と旅行者の歩行の進行の指定 {
            開閉の規則: self.開閉の規則.clone(),
            開閉の状態: 状態.開閉.clone(),
            居場所: 状態.居場所.clone(),
            身体: self.身体,
        });
        let 入力 = 経路の開閉と旅行者の歩行の更新への入力 {
            開閉の命令: 命令.clone(), 旅行者の意図: *意図
        };
        let 結果 = match 始めた.map(|進行| 進行.経路の開閉と旅行者の歩行を1回更新する(&入力, 刻み(0.0, 1.0))) {
            Ok(結果) if 結果.失敗一覧.is_empty() => 結果,
            失敗 => {
                return 遷移の帰結::失敗 {
                    元の状態: 状態.clone(),
                    説明: format!("{:?}", 失敗.map(|結果| 結果.失敗一覧)),
                };
            }
        };
        let 出来事一覧 = 結果.開閉の出来事一覧.into_iter().map(旅の出来事::開閉).chain(結果.旅行者の出来事一覧.into_iter().map(旅の出来事::旅行者)).collect();
        遷移の帰結::成功 {
            次の状態: 旅の状態 {
                開閉: 結果.次の進行.開閉の状態().clone(),
                居場所: 結果.次の進行.居場所().clone(),
            },
            出来事一覧,
        }
    }

    fn 状態の同一性を答える(&self, 状態: &旅の状態) -> 旅の状態の同一性 {
        旅の状態の同一性(旅の状態の表記(状態))
    }

    fn 状態を名指す(&self, 状態: &旅の状態) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(旅の名前の空間, &旅の状態の表記(状態))
    }

    fn コマンドを名指す(&self, コマンド: &旅のコマンド) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(旅の名前の空間, &format!("旅のコマンド({コマンド:?})"))
    }

    fn 出来事を名指す(&self, 出来事: &旅の出来事) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(旅の名前の空間, &format!("旅の出来事({出来事:?})"))
    }

    fn 規則を名指す(&self) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(旅の名前の空間, "経路の開閉と旅行者の歩行の進行")
    }
}
