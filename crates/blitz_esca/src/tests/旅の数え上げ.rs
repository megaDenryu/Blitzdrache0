//! 経路の開閉と旅行者の歩行の遷移(経路の開閉と旅行者の歩行を合わせた遷移)を、小さな地図の全状態で数え上げる、有限に数え上げられる領域(Issue #187 の作業G2)。
//!
//! 状態・コマンド・出来事は実物の型(`経路の開閉と旅行者の歩行の状態`・`経路の開閉と旅行者の歩行の更新への入力`・`経路の開閉と旅行者の歩行の出来事`)であり、地図と状態の表記は `旅の数え上げの試料.rs` が持つ。
//! 旅行者は村の(5, 5)から始まり、1刻みに5メートル歩く。どの通り口も境目の真ん中(5メートルの位置)にあり、区域の端も5メートルの倍数にあるため、
//! 現在地はいつも5メートルの格子の上にあり、状態は有限である。コマンドは、開閉の命令と旅行者の意図の命令の組である。
//! 開閉の命令は命令が無いと峠道を閉じる・開くの3つであり、関所を開ける命令を入れるかは領域を組むときに選ぶ(入れない領域では城下町へ入れないことを確かめる)。
//! どちらの数え上げも取りうる値を全部並べるため、網羅性は全件を数え上げたで返る。
//!
//! `一回遷移する` は `経路の開閉と旅行者の歩行の状態::経路の開閉と旅行者の歩行を1回更新する` をそのまま呼び、1刻みの順序と2つの遷移の意味を試験の側へ書き写さない(Issue #173 が禁じた形)。
//! 1刻みは失敗しない遷移であり、区域の外にいる居場所と地図に無い経路の命令はプログラムの誤りとして遷移を停止させる(設計オントロジー 3.5.9)。
//! そのため、探索が停止せずに全件を数え上げたことが、到達可能な全状態で旅行者が自分の地点の区域の中にいることを意味する。

#![allow(clippy::expect_used)]

use blitz_design_verification::{数え上げ, 有限に数え上げられる領域, 設計概念への参照, 遷移の帰結};
use blitz_math::メートル毎秒;

use super::一つの区域の試料::現在地;
use super::地点と経路の試料::{刻み, 封鎖できる経路を指す};
use super::旅の数え上げの試料::{城下町の地図を組む, 旅の名前の空間, 旅の状態の同一性, 旅の状態の表記};
use crate::walking_direction::歩行方向;
use crate::地点と経路::地点と経路の図式::地点Id;
use crate::地点と経路::{経路の開閉の命令, 経路の開閉の規則};
use crate::居場所::旅行者の居場所;
use crate::旅行者::{旅行者の意図, 歩行の規則};
use crate::経路の開閉と旅行者の歩行::{
    経路の開閉と旅行者の歩行の出来事, 経路の開閉と旅行者の歩行の更新への入力, 経路の開閉と旅行者の歩行の状態, 経路の開閉と旅行者の歩行の規則
};

/// 実物の `経路の開閉と旅行者の歩行の状態::経路の開閉と旅行者の歩行を1回更新する` を呼ぶ領域。
pub struct 旅を数え上げる領域 {
    規則: 経路の開閉と旅行者の歩行の規則,
    関所を開ける命令を入れるか: bool,
}

impl 旅を数え上げる領域 {
    /// 城下町の地図と、1刻みに5メートル歩く身体で領域を組む。関所を開ける命令をコマンドへ入れるかを選ぶ。
    pub fn 生成する(関所を開ける命令を入れるか: bool) -> Self {
        let 身体 = 歩行の規則::生成する(メートル毎秒::生成する(5.0)).expect("有限な正の速さは規則になるべきである");
        Self {
            規則: 経路の開閉と旅行者の歩行の規則::生成する(経路の開閉の規則::生成する(城下町の地図を組む()), 身体),
            関所を開ける命令を入れるか,
        }
    }
}

impl 有限に数え上げられる領域 for 旅を数え上げる領域 {
    type 状態 = 経路の開閉と旅行者の歩行の状態;
    type コマンド = 経路の開閉と旅行者の歩行の更新への入力;
    type 出来事 = 経路の開閉と旅行者の歩行の出来事;
    type 状態の同一性 = 旅の状態の同一性;

    fn 初期状態を数え上げる(&self) -> 数え上げ<経路の開閉と旅行者の歩行の状態> {
        let 開閉の規則 = self.規則.開閉の規則();
        let 村 = 開閉の規則.地図().地点を確かめる(&地点Id("村".to_string())).expect("村は地図に在る");
        数え上げ::全件(vec![経路の開閉と旅行者の歩行の状態::生成する(開閉の規則.はじめの状態(), 旅行者の居場所::生成する(村, 現在地(5.0, 5.0)))])
    }

    fn 状態で試すコマンドを数え上げる(&self, _状態: &経路の開閉と旅行者の歩行の状態) -> 数え上げ<経路の開閉と旅行者の歩行の更新への入力> {
        let 峠道 = 封鎖できる経路を指す(self.規則.開閉の規則().地図(), "峠道");
        let mut 命令一覧 = vec![経路の開閉の命令::命令が無い, 経路の開閉の命令::経路を閉じる { 経路: 峠道.clone() }, 経路の開閉の命令::経路を開く { 経路: 峠道 }];
        if self.関所を開ける命令を入れるか {
            命令一覧.push(経路の開閉の命令::経路を開く {
                経路: 封鎖できる経路を指す(self.規則.開閉の規則().地図(), "関所"),
            });
        }
        let 意図一覧 = [
            旅行者の意図::静止,
            旅行者の意図::歩く { 方向: 歩行方向::東() },
            旅行者の意図::歩く { 方向: 歩行方向::西() },
            旅行者の意図::歩く { 方向: 歩行方向::北() },
            旅行者の意図::歩く { 方向: 歩行方向::南() },
        ];
        数え上げ::全件(命令一覧.iter().flat_map(|命令| 意図一覧.iter().map(|意図| 経路の開閉と旅行者の歩行の更新への入力::生成する(命令.clone(), *意図))).collect())
    }

    /// 実物の1刻みを呼ぶ。1刻みは失敗しないため、帰結はいつも成功である。
    fn 一回遷移する(
        &self, 状態: &経路の開閉と旅行者の歩行の状態, コマンド: &経路の開閉と旅行者の歩行の更新への入力
    ) -> 遷移の帰結<経路の開閉と旅行者の歩行の状態, 経路の開閉と旅行者の歩行の出来事> {
        match 状態.clone().経路の開閉と旅行者の歩行を1回更新する(コマンド, &self.規則, 刻み(0.0, 1.0)) {
            Ok(成功) => 遷移の帰結::成功 {
                次の状態: 成功.次の状態,
                出来事一覧: 成功.出来事一覧,
            },
            Err(失敗) => match 失敗.失敗の理由 {},
        }
    }

    fn 状態の同一性を答える(&self, 状態: &経路の開閉と旅行者の歩行の状態) -> 旅の状態の同一性 {
        旅の状態の同一性(旅の状態の表記(状態))
    }

    fn 状態を名指す(&self, 状態: &経路の開閉と旅行者の歩行の状態) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(旅の名前の空間, &旅の状態の表記(状態))
    }

    fn コマンドを名指す(&self, コマンド: &経路の開閉と旅行者の歩行の更新への入力) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(旅の名前の空間, &format!("{コマンド:?}"))
    }

    fn 出来事を名指す(&self, 出来事: &経路の開閉と旅行者の歩行の出来事) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(旅の名前の空間, &format!("{出来事:?}"))
    }

    fn 規則を名指す(&self) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(旅の名前の空間, "経路の開閉と旅行者の歩行の規則")
    }
}
