//! 旅の1刻みを小さな地図の全状態で数え上げ、区域と開閉の2つの性質を確かめる試験(Issue #187 の作業G2)。
//!
//! 確かめる性質は2つである。(1) 閉じた門(関所)しか通り口の無い区域(城下町)へは入れない。関所を開ける命令を入れない領域の、到達可能な全状態のどれも城下町にいない。
//! (2) 旅行者はいつもどこかの区域にいる。歩行の遷移は、居場所がいる地点の区域の外にあれば失敗するため、全件を数え上げた探索で失敗した遷移が1件も無いことは、
//! 到達可能な全状態で旅行者が自分の地点の区域の中にいることを意味する(どの状態からも、静止の意図の遷移がその確かめを通る)。
//! 空虚に通らないことを、関所を開ける命令を入れた領域では城下町へ入れることで確かめる。
//! 網羅性が全件を数え上げたであるときだけ、全状態についての主張として読める。
//!
//! 全状態の主張が及ぶのは、この小さな地図(軸に揃った一辺10メートルの正方形の区域・5メートルの格子の現在地・軸方向の4つの向き)の上だけである。
//! 歩行は斜めの壁・境界の許容幅・滑り・凹んだ頂点を通らないため、それらの上で(2)が成り立つことは単体の試験
//! (`境目の許容幅の近くの歩行の試験.rs`・`区域の閉包に留まる歩行の試験.rs`)が標本で確かめる。
//! (1)と(2)を命題の構文で書かず遷移モデルを直接見るのは、振る舞いの原子命題(発生する・遷移する・到達可能である)に、
//! 状態の中身(いる地点・現在地が区域に入るか)を問うものも、遷移が失敗したかを問うものも無いためである。

#![allow(clippy::expect_used)]

use blitz_design_verification::{探索が組んだ遷移モデルと網羅性, 探索の上限, 数え上げの網羅性, 領域から遷移モデルを組む};

use super::旅の数え上げ::旅を数え上げる領域;

// 探索してよい状態の件数。5メートルの格子の現在地と開閉の状態の組は、これより十分に少ない。
const 探索してよい状態の件数: usize = 100_000;

fn 数え上げる(関所を開ける命令を入れるか: bool) -> 探索が組んだ遷移モデルと網羅性 {
    let 領域 = 旅を数え上げる領域::生成する(関所を開ける命令を入れるか);
    領域から遷移モデルを組む(&領域, 探索の上限::生成する(探索してよい状態の件数)).unwrap_or_else(|食い違い| panic!("{食い違い}"))
}

// その地点にいる到達可能な状態の件数。状態の名指しの表記が「地点: 名前 」を含むかで数える。
fn その地点にいる到達可能な状態の件数(探索の結果: &探索が組んだ遷移モデルと網羅性, 地点の名前: &str) -> usize {
    let 目印 = format!("地点: {地点の名前} ");
    探索の結果.モデル.到達可能な状態一覧を組む().到達順の一覧().iter().filter(|状態| 状態.表記().contains(&目印)).count()
}

#[test]
fn 旅の数え上げは全件を数え上げたと答える() {
    for 関所を開ける命令を入れるか in [false, true] {
        let 網羅性 = 数え上げる(関所を開ける命令を入れるか).網羅性;
        assert_eq!(網羅性, 数え上げの網羅性::全件を数え上げた, "{}", 網羅性.表記());
    }
}

#[test]
fn 閉じた門しか通り口の無い区域へは全状態で入れない() {
    let 探索の結果 = 数え上げる(false);
    assert_eq!(探索の結果.網羅性, 数え上げの網羅性::全件を数え上げた);
    assert_eq!(その地点にいる到達可能な状態の件数(&探索の結果, "城下町"), 0, "関所が閉じたままなのに城下町にいる状態へ到達した");
    assert!(その地点にいる到達可能な状態の件数(&探索の結果, "峠") > 0, "この領域は峠道を通って峠へ入れるべきである(探索が村から出ていない)");
    assert!(その地点にいる到達可能な状態の件数(&探索の結果, "港") > 0, "この領域は山道を通って港へ入れるべきである");
}

#[test]
fn 関所を開ける命令があれば城下町へ入れる() {
    let 探索の結果 = 数え上げる(true);
    assert!(その地点にいる到達可能な状態の件数(&探索の結果, "城下町") > 0, "関所を開けても城下町へ入れていない(前の試験が空虚に通っている)");
}

#[test]
fn 旅行者はいつもどこかの区域にいて失敗した遷移が1件も無い() {
    for 関所を開ける命令を入れるか in [false, true] {
        let 探索の結果 = 数え上げる(関所を開ける命令を入れるか);
        let 失敗した件数 = 探索の結果.モデル.遷移一覧().iter().filter(|遷移| 遷移.失敗().is_some()).count();
        assert_eq!(探索の結果.網羅性, 数え上げの網羅性::全件を数え上げた);
        assert_eq!(失敗した件数, 0, "区域の外にいる居場所の遷移か、地図に無い経路の命令が起きた");
    }
}
