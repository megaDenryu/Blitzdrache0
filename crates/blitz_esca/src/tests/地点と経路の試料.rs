//! 地点と経路の試験が共有する地図と時刻(Issue #187 の作業G1)。
//!
//! 試験の地図は地点4つ(村・峠・城下町・港)と経路4本(峠道・関所・橋・渡し)を持つ。峠道は10秒から20秒まで閉じている時間帯を持ち、
//! 関所ははじめから閉じている。残りの2本は時間帯を持たず、はじめは開いている。
//! 地図の外の経路を指す識別子は、峠と港を隠し道でつなぐ別の地図から取る。識別子は地図が確かめてから渡すため、
//! 試験の地図に無い経路を指す識別子を作る手段は、別の地図に確かめさせることだけである。

#![allow(clippy::expect_used)]

use blitz_math::{大域秒, 秒};

use crate::elapsed_time::経過時間;
use crate::transition_parameter::遷移パラメータ;
use crate::地点と経路::地点と経路の図式::経路Id;
use crate::地点と経路::{地点, 地点と経路のグラフ, 地点と経路の図式, 経路の識別子, 経路の開閉, 経路の開閉の予定, 経路の開閉の規則, 閉じている時間帯の指定};
use crate::時刻::世界の時刻;

pub const 峠道が閉じる秒: f64 = 10.0; // 峠道が閉じている時間帯の始まりの秒
pub const 峠道が開く秒: f64 = 20.0; // 峠道が閉じている時間帯の終わりの秒

/// 地点4つと経路4本の試験の地図。
pub fn 試験の地図を組む() -> 地点と経路のグラフ {
    #[rustfmt::skip]
    let つながり = graphite::graph!(地点と経路の図式 {
        村 = 地点 {},
        峠 = 地点 {},
        城下町 = 地点 {},
        港 = 地点 {},
        峠道 = 経路(村 -[峠道の予定()]- 峠),
        関所 = 経路(峠 -[経路の開閉の予定::時間帯を持たない(経路の開閉::閉じている)]- 城下町),
        橋 = 経路(城下町 -[経路の開閉の予定::時間帯を持たない(経路の開閉::開いている)]- 港),
        渡し = 経路(村 -[経路の開閉の予定::時間帯を持たない(経路の開閉::開いている)]- 港),
    })
    .expect("多重度の制約を持たない図式の地図は組めるべきである");
    地点と経路のグラフ::生成する(つながり.into_graph())
}

/// 試験の地図を持つ規則。
pub fn 試験の規則を組む() -> 経路の開閉の規則 {
    経路の開閉の規則::生成する(試験の地図を組む())
}

/// 峠と港を隠し道1本でつなぐ別の地図。隠し道の識別子が、試験の地図に無い経路を指す識別子になる。
pub fn 隠し道だけの地図を組む() -> 地点と経路のグラフ {
    #[rustfmt::skip]
    let つながり = graphite::graph!(地点と経路の図式 {
        峠 = 地点 {},
        港 = 地点 {},
        隠し道 = 経路(峠 -[経路の開閉の予定::時間帯を持たない(経路の開閉::開いている)]- 港),
    })
    .expect("多重度の制約を持たない図式の地図は組めるべきである");
    地点と経路のグラフ::生成する(つながり.into_graph())
}

/// その地図が確かめた、その名前の経路の識別子。
pub fn 経路を指す(地図: &地点と経路のグラフ, 名前: &str) -> 経路の識別子 {
    地図.経路を確かめる(&経路Id(名前.to_string())).expect("試料の地図に在る名前だけを渡すべきである")
}

/// 試験の地図に無い経路(隠し道)を指す識別子。
pub fn 地図の外の経路() -> 経路の識別子 {
    経路を指す(&隠し道だけの地図を組む(), "隠し道")
}

pub fn 時刻(秒数: f64) -> 世界の時刻 {
    世界の時刻::生成する(大域秒::生成する(秒数)).expect("有限な0以上の秒数は世界の時刻になるべきである")
}

/// 始まりの秒から経過の秒だけ進む刻みの遷移パラメータ。
pub fn 刻み(始まりの秒数: f64, 経過の秒数: f32) -> 遷移パラメータ {
    遷移パラメータ::最初の刻みを生成する(時刻(始まりの秒数), 経過時間::生成する(秒::生成する(経過の秒数)).expect("有限な0以上の秒数は経過時間になるべきである"))
}

fn 峠道の予定() -> 経路の開閉の予定 {
    let 時間帯 = 閉じている時間帯の指定 {
        始まり: 時刻(峠道が閉じる秒),
        終わり: 時刻(峠道が開く秒),
    }
    .検証する()
    .expect("始まりが終わりより前の時間帯は検証を通るべきである");
    経路の開閉の予定::生成する(経路の開閉::開いている, vec![時間帯]).expect("時間帯1つの予定は検証を通るべきである")
}
