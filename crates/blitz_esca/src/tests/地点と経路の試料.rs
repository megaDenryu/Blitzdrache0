/// 南西の角が(東, 北)にある、一辺10メートルの正方形の区域。各辺を4メートルと6メートルの位置で分けた12個の頂点を反時計回りに並べる。
pub fn 正方形の区域(南西の東: f32, 南西の北: f32) -> 区域 {
    let 刻み = [(0.0, 0.0), (4.0, 0.0), (6.0, 0.0), (10.0, 0.0), (10.0, 4.0), (10.0, 6.0), (10.0, 10.0), (6.0, 10.0), (4.0, 10.0), (0.0, 10.0), (0.0, 6.0), (0.0, 4.0)];
    let 頂点一覧 = 刻み
        .iter()
        .map(|(東, 北)| 区域の頂点 {
            東: メートル::生成する(南西の東 + 東),
            北: メートル::生成する(南西の北 + 北),
        })
        .collect();
    区域の指定 { 頂点一覧 }.検証する().expect("反時計回りの正方形は区域になるべきである")
}

/// 片方の区域の辺ともう片方の区域の辺で指す通り口。
pub fn 通り口(片方の区域の辺: 区域の辺の番号, もう片方の区域の辺: 区域の辺の番号) -> 通り口の指定 {
    通り口の指定 {
        片方の区域の辺, もう片方の区域の辺
    }
}

/// 地点4つと経路5本の試験の地図。
pub fn 試験の地図を組む() -> 地点と経路のグラフ {
    let 開いている = || 経路の開閉の予定::時間帯を持たない(経路の開閉::開いている);
    #[rustfmt::skip]
    let つながり = graphite::graph!(地点と経路の図式 {
        村 = 地点::区域で生成する(正方形の区域(0.0, 0.0)),
        峠 = 地点::区域で生成する(正方形の区域(区域の一辺, 0.0)),
        城下町 = 地点::区域で生成する(正方形の区域(区域の一辺, 区域の一辺)),
        港 = 地点::区域で生成する(正方形の区域(0.0, 区域の一辺)),
        峠道 = 経路(村 -[経路の積み荷::生成する(経路の種類::幹線道路, 通り口(東の真ん中の辺, 西の真ん中の辺), 峠道の予定())]- 峠),
        関所 = 経路(峠 -[経路の積み荷::生成する(経路の種類::門, 通り口(北の真ん中の辺, 南の真ん中の辺), 経路の開閉の予定::時間帯を持たない(経路の開閉::閉じている))]- 城下町),
        橋 = 経路(城下町 -[経路の積み荷::生成する(経路の種類::橋, 通り口(西の真ん中の辺, 東の真ん中の辺), 開いている())]- 港),
        渡し = 経路(港 -[経路の積み荷::生成する(経路の種類::門, 通り口(南の真ん中の辺, 北の真ん中の辺), 開いている())]- 村),
        抜け道 = 経路(村 -[経路の積み荷::予定を持たずに生成する(経路の種類::脇道, 通り口(東の南の端の辺, 西の南の端の辺))]- 峠),
    })
    .expect("多重度の制約を持たない図式の地図は組めるべきである");
    地点と経路のグラフ::検証して生成する(つながり.into_graph()).expect("区域と通り口の不変条件を満たす試験の地図は検証を通るべきである")
}

/// 試験の地図を持つ規則。
pub fn 試験の規則を組む() -> 経路の開閉の規則 {
    経路の開閉の規則::生成する(試験の地図を組む())
}

/// 2つの地点を隠し道(門)1本でつなぐ別の地図。隠し道の識別子が、試験の地図に無い経路を指す識別子になる。
pub fn 隠し道だけの地図を組む() -> 地点と経路のグラフ {
    #[rustfmt::skip]
    let つながり = graphite::graph!(地点と経路の図式 {
        峠 = 地点::区域で生成する(正方形の区域(0.0, 0.0)),
        港 = 地点::区域で生成する(正方形の区域(区域の一辺, 0.0)),
        隠し道 = 経路(峠 -[経路の積み荷::生成する(経路の種類::門, 通り口(東の真ん中の辺, 西の真ん中の辺), 経路の開閉の予定::時間帯を持たない(経路の開閉::開いている))]- 港),
    })
    .expect("多重度の制約を持たない図式の地図は組めるべきである");
    地点と経路のグラフ::検証して生成する(つながり.into_graph()).expect("区域と通り口の不変条件を満たす地図は検証を通るべきである")
}

/// その地図が確かめた、その名前の経路の識別子。
pub fn 経路を指す(地図: &地点と経路のグラフ, 名前: &str) -> 経路の識別子 {
    地図.経路を確かめる(&経路Id(名前.to_string())).expect("試料の地図に在る名前だけを渡すべきである")
}

/// その地図が確かめた、その名前の封鎖できる経路の識別子。
pub fn 封鎖できる経路を指す(地図: &地点と経路のグラフ, 名前: &str) -> 封鎖できる経路の識別子 {
    地図.封鎖できる経路として確かめる(&経路を指す(地図, 名前)).expect("試料の地図の封鎖できる経路の名前だけを渡すべきである")
}

/// 試験の地図に無い経路(隠し道)を指す識別子。
pub fn 地図の外の経路() -> 封鎖できる経路の識別子 {
    封鎖できる経路を指す(&隠し道だけの地図を組む(), "隠し道")
}

pub fn 時刻(秒数: f64) -> 世界の時刻 {
    世界の時刻::生成する(大域秒::生成する(秒数)).expect("有限な0以上の秒数は世界の時刻になるべきである")
}

/// 始まりの秒から経過の秒だけ進む刻みの遷移パラメータ。
pub fn 刻み(始まりの秒数: f64, 経過の秒数: f32) -> 遷移パラメータ {
    遷移パラメータ::最初の刻みを生成する(時刻(始まりの秒数), 経過時間::生成する(秒::生成する(経過の秒数)).expect("有限な0以上の秒数は経過時間になるべきである"))
}

fn 峠道の予定() -> 経路の開閉の予定 {
    let 時間帯 = 閉じている時間帯の指定 {
        始まり: 時刻(峠道が閉じる秒),
        終わり: 時刻(峠道が開く秒),
    }
    .検証する()
    .expect("始まりが終わりより前の時間帯は検証を通るべきである");
    経路の開閉の予定::生成する(経路の開閉::開いている, vec![時間帯]).expect("時間帯1つの予定は検証を通るべきである")
}
