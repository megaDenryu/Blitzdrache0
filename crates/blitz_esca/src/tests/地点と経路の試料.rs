//! 地点と経路の試験が共有する地図と時刻(Issue #187 の作業G1・G2)。
//!
//! 試験の地図は地点4つと経路5本を持つ。地点の区域は一辺10メートルの正方形であり、村(南西)・峠(南東)・城下町(北東)・港(北西)の順に反時計回りに隣り合う。
//! 正方形の頂点は南西の角から反時計回りに12個並び、各辺は4メートルと6メートルの位置で3本の辺に分かれる(辺の番号の定数はこの並びの番号である)。隣の区域との境目の真ん中の辺(長さ2メートル)が通り口になる。
//! 経路は峠道(村と峠。幹線道路。10秒から20秒まで閉じている時間帯を持つ)・関所(峠と城下町。門。はじめから閉じている)・橋(城下町と港。橋)・
//! 渡し(港と村。門)の4本と、村と峠の境目の南の端の辺を通る抜け道(脇道。封鎖できない)の1本である。
//! 地図の外の経路を指す識別子は、2つの地点を隠し道(門)でつなぐ別の地図から取る。識別子は地図が確かめてから渡すため、
//! 試験の地図に無い経路を指す識別子を作る手段は、別の地図に確かめさせることだけである。

