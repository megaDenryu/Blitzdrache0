pub const 区域の一辺: f32 = 10.0; // 試験の地図の正方形の区域の一辺のメートル
pub const 南の真ん中の辺: 区域の辺の番号 = 区域の辺の番号::生成する(1);
pub const 東の南の端の辺: 区域の辺の番号 = 区域の辺の番号::生成する(3);
pub const 東の真ん中の辺: 区域の辺の番号 = 区域の辺の番号::生成する(4);
pub const 北の真ん中の辺: 区域の辺の番号 = 区域の辺の番号::生成する(7);
