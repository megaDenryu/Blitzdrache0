//! 旅行者の歩行遷移計算と描画射影の機能テスト(Issue #137)。

#![allow(clippy::expect_used)]

use blitz_math::{メートル, 秒};

use crate::ontology::遷移結果;
use crate::traveler::{旅行者の出来事, 旅行者の意図, 旅行者の現在地, 歩行の規則};
use crate::traveler_boundary::移動可能範囲の指定;
use crate::traveler_movement::歩行遷移の規則;
use crate::walking_direction::歩行方向;

fn 現在地(東: f32, 北: f32) -> 旅行者の現在地 {
    旅行者の現在地::生成する(メートル::生成する(東), メートル::生成する(北))
}

#[test]
fn 歩行遷移計算_制約なしの空間では速さと経過時間の積だけ進んで歩行開始出来事が発行される() {
    let 規則 = 歩行遷移の規則::制約なし(歩行の規則::標準());
    let 結果 = 現在地(10.0, 20.0).歩行を遷移する(&旅行者の意図::歩く { 方向: 歩行方向::東() }, &規則, 秒::生成する(2.0));
    assert_eq!(
        結果,
        遷移結果 {
            次の状態: 現在地(16.0, 20.0),
            出来事一覧: vec![旅行者の出来事::歩行を開始した]
        }
    );
}

#[test]
fn 歩行遷移計算_静止の意図では現在地は変化せず立ち止まった出来事が発行される() {
    let 規則 = 歩行遷移の規則::制約なし(歩行の規則::標準());
    let 結果 = 現在地(5.0, 5.0).歩行を遷移する(&旅行者の意図::静止, &規則, 秒::生成する(1.0));
    assert_eq!(
        結果,
        遷移結果 {
            次の状態: 現在地(5.0, 5.0),
            出来事一覧: vec![旅行者の出来事::立ち止まった]
        }
    );
}

#[test]
fn 歩行遷移計算_壁に突き当たると座標が制限され障害物に遮られた出来事が発行される() {
    let 境界 = 移動可能範囲の指定 {
        東の最小: メートル::生成する(0.0),
        東の最大: メートル::生成する(10.0),
        北の最小: メートル::生成する(-10.0),
        北の最大: メートル::生成する(10.0),
    }
    .検証する()
    .expect("最小が最大以下の指定は検証を通るべきである");
    let 規則 = 歩行遷移の規則::空間制約付き(歩行の規則::標準(), 境界);
    // 8.0mから3.0m/sで1秒歩くと11.0mになるが、東の最大10.0mで制限される
    let 結果 = 現在地(8.0, 0.0).歩行を遷移する(&旅行者の意図::歩く { 方向: 歩行方向::東() }, &規則, 秒::生成する(1.0));
    assert_eq!(
        結果,
        遷移結果 {
            次の状態: 現在地(10.0, 0.0),
            出来事一覧: vec![旅行者の出来事::障害物に遮られた]
        }
    );
}

#[test]
fn 描画射影_ゲーム状態の現在地から描画用位置dtoを正確に取り出せる() {
    let 描画位置 = 現在地(12.5, 8.0).描画位置を射影する();
    assert_eq!(描画位置.東メートル, メートル::生成する(12.5));
    assert_eq!(描画位置.北メートル, メートル::生成する(8.0));
}
