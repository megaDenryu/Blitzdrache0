//! 旅行者の歩行遷移計算と描画射影の機能テスト(Issue #137)。

#![allow(clippy::expect_used)]

use blitz_math::{メートル, メートル毎秒, 秒};

use crate::elapsed_time::経過時間;
use crate::ontology::遷移結果;
use crate::traveler::{旅行者の出来事, 旅行者の意図, 旅行者の現在地, 歩行の規則};
use crate::traveler_boundary::移動可能範囲の指定;
use crate::traveler_error::歩行の規則の生成の失敗;
use crate::traveler_movement::歩行遷移の規則;
use crate::walking_direction::歩行方向;

fn 現在地(東: f32, 北: f32) -> 旅行者の現在地 {
    旅行者の現在地::生成する(メートル::生成する(東), メートル::生成する(北))
}

fn 経過(秒数: f32) -> 経過時間 {
    経過時間::生成する(秒::生成する(秒数)).expect("有限な0以上の秒数は経過時間になるべきである")
}

#[test]
fn 歩行遷移計算_制約なしの空間では速さと経過時間の積だけ進み出来事は無い() {
    let 規則 = 歩行遷移の規則::制約なし(歩行の規則::標準());
    let 結果 = 現在地(10.0, 20.0).歩行を遷移する(&旅行者の意図::歩く { 方向: 歩行方向::東() }, &規則, 経過(2.0));
    assert_eq!(
        結果,
        遷移結果 {
            次の状態: 現在地(16.0, 20.0),
            出来事一覧: vec![]
        }
    );
}

#[test]
fn 歩行遷移計算_静止の意図では現在地は変化せず出来事は無い() {
    let 規則 = 歩行遷移の規則::制約なし(歩行の規則::標準());
    let 結果 = 現在地(5.0, 5.0).歩行を遷移する(&旅行者の意図::静止, &規則, 経過(1.0));
    assert_eq!(
        結果,
        遷移結果 {
            次の状態: 現在地(5.0, 5.0),
            出来事一覧: vec![]
        }
    );
}

#[test]
fn 歩行遷移計算_壁に突き当たると座標が制限され障害物に遮られた出来事が発行される() {
    let 境界 = 移動可能範囲の指定 {
        東の最小: メートル::生成する(0.0),
        東の最大: メートル::生成する(10.0),
        北の最小: メートル::生成する(-10.0),
        北の最大: メートル::生成する(10.0),
    }
    .検証する()
    .expect("最小が最大以下の指定は検証を通るべきである");
    let 規則 = 歩行遷移の規則::空間制約付き(歩行の規則::標準(), 境界);
    // 8.0mから3.0m/sで1秒歩くと11.0mになるが、東の最大10.0mで制限される
    let 結果 = 現在地(8.0, 0.0).歩行を遷移する(&旅行者の意図::歩く { 方向: 歩行方向::東() }, &規則, 経過(1.0));
    assert_eq!(
        結果,
        遷移結果 {
            次の状態: 現在地(10.0, 0.0),
            出来事一覧: vec![旅行者の出来事::障害物に遮られた]
        }
    );
}

#[test]
