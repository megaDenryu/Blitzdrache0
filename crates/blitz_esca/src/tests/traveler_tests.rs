//! 旅行者の歩行遷移計算と描画射影の機能テスト(Issue #137)。

use blitz_math::メートル;

use crate::traveler::{旅行者の出来事, 旅行者の意図, 旅行者の現在地, 歩行の規則};
use crate::traveler_boundary::移動可能範囲;
use crate::traveler_movement::{描画位置を射影する, 歩行を遷移する, 歩行遷移の規則};

#[test]
fn 境界制限_空間内ではそのままの座標を返し衝突フラグは偽() {
    let 境界 = 移動可能範囲 {
        東の最小: メートル::生成する(-10.0),
        東の最大: メートル::生成する(10.0),
        北の最小: メートル::生成する(-10.0),
        北の最大: メートル::生成する(10.0),
    };
    let 結果 = 境界.制限する(メートル::生成する(3.0), メートル::生成する(5.0));
    assert_eq!(結果.制限後の東.値(), 3.0);
    assert_eq!(結果.制限後の北.値(), 5.0);
    assert!(!結果.衝突した);
}

#[test]
fn 歩行遷移計算_制約なしの空間では指定秒数進んで歩行開始出来事が発行される() {
    let 初期位置 = 旅行者の現在地::生成する(メートル::生成する(10.0), メートル::生成する(20.0));
    let 意図 = 旅行者の意図::歩く { 東の比率: 1.0, 北の比率: 0.0 };
    let 身体規則 = 歩行の規則::標準();
    let 規則 = 歩行遷移の規則::制約なし(身体規則);

    let (次の現在地, 出来事一覧) = 歩行を遷移する(&初期位置, &意図, &規則, 2.0);

    assert_eq!(次の現在地.東().値(), 16.0);
    assert_eq!(次の現在地.北().値(), 20.0);
    assert_eq!(出来事一覧, vec![旅行者の出来事::歩行を開始した]);
}

#[test]
fn 歩行遷移計算_静止の意図では現在地は変化せず立ち止まった出来事が発行される() {
    let 初期位置 = 旅行者の現在地::生成する(メートル::生成する(5.0), メートル::生成する(5.0));
    let 意図 = 旅行者の意図::静止;
    let 身体規則 = 歩行の規則::標準();
    let 規則 = 歩行遷移の規則::制約なし(身体規則);

    let (次の現在地, 出来事一覧) = 歩行を遷移する(&初期位置, &意図, &規則, 1.0);

    assert_eq!(次の現在地, 初期位置);
    assert_eq!(出来事一覧, vec![旅行者の出来事::立ち止まった]);
}

#[test]
fn 歩行遷移計算_壁に突き当たると座標が制限され障害物に遮られた出来事が発行される() {
    let 初期位置 = 旅行者の現在地::生成する(メートル::生成する(8.0), メートル::生成する(0.0));
    let 意図 = 旅行者の意図::歩く { 東の比率: 1.0, 北の比率: 0.0 };
    let 身体規則 = 歩行の規則::標準();
    let 境界 = 移動可能範囲 {
        東の最小: メートル::生成する(0.0),
        東の最大: メートル::生成する(10.0),
        北の最小: メートル::生成する(-10.0),
        北の最大: メートル::生成する(10.0),
    };
    let 規則 = 歩行遷移の規則::空間制約付き(身体規則, 境界);

    // 8.0mから3.0m/sで1秒歩くと11.0mになるが、東の最大10.0mで制限される
    let (次の現在地, 出来事一覧) = 歩行を遷移する(&初期位置, &意図, &規則, 1.0);

    assert_eq!(次の現在地.東().値(), 10.0);
    assert_eq!(出来事一覧, vec![旅行者の出来事::障害物に遮られた]);
}

#[test]
fn 描画射影_ゲーム状態の現在地から描画用位置dtoを正確に取り出せる() {
    let 現在地 = 旅行者の現在地::生成する(メートル::生成する(12.5), メートル::生成する(8.0));
    let 描画位置 = 描画位置を射影する(&現在地);

    assert_eq!(描画位置.東メートル, 12.5);
    assert_eq!(描画位置.北メートル, 8.0);
}
