    let 境界 = 移動可能範囲の指定 {
        東の最小: メートル::生成する(0.0),
        東の最大: メートル::生成する(10.0),
        北の最小: メートル::生成する(-10.0),
        北の最大: メートル::生成する(10.0),
    }
    .検証する()
    .expect("最小が最大以下の指定は検証を通るべきである");
    let 規則 = 歩行遷移の規則::空間制約付き(歩行の規則::標準(), 境界);
    let 結果 = 現在地(2.0, 0.0).歩行を遷移する(&旅行者の意図::歩く { 方向: 歩行方向::東() }, &規則, 経過(1.0));
