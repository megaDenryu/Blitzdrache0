//! 旅行者の歩行遷移計算と描画射影の機能テスト(Issue #137。Issue #187 の作業G2で、長方形の移動可能範囲を1つの区域へ置き換えた)。
//! 生成の口の不変条件は `traveler_invariant_tests.rs` が固定する。

#![allow(clippy::expect_used)]

use blitz_math::メートル;

use super::一つの区域の試料::{現在地, 経過, 長方形の端};
use crate::ontology::遷移成功結果;
use crate::traveler::{旅行者の出来事, 旅行者の意図, 旅行者の現在地, 歩行の規則};
use crate::walking_direction::歩行方向;

// 境界に届かない、東西と南北に2000メートルの広場。
fn 広い広場() -> 長方形の端 {
    長方形の端 {
        東の最小: -1000.0,
        東の最大: 1000.0,
        北の最小: -1000.0,
        北の最大: 1000.0,
    }
}

// 東が0から10メートル、北が-10から10メートルの広場。
fn 東に壁のある広場() -> 長方形の端 {
    長方形の端 {
        東の最小: 0.0,
        東の最大: 10.0,
        北の最小: -10.0,
        北の最大: 10.0,
    }
}

#[test]
fn 歩行遷移計算_境界に届かない広場では速さと経過時間の積だけ進み出来事は無い() {
    let 広場 = 広い広場();
    let 結果 = 広場
        .広場の居場所(現在地(10.0, 20.0))
        .歩行を遷移する(&旅行者の意図::歩く { 方向: 歩行方向::東() }, &広場.歩行の規則を組む(歩行の規則::標準()), 経過(2.0))
        .expect("区域の中の遷移は成功するべきである");
    assert_eq!(
        結果,
        遷移成功結果 {
            次の状態: 広場.広場の居場所(現在地(16.0, 20.0)),
            出来事一覧: vec![]
        }
    );
}

#[test]
fn 歩行遷移計算_静止の意図では居場所は変化せず出来事は無い() {
    let 広場 = 広い広場();
    let 結果 = 広場
        .広場の居場所(現在地(5.0, 5.0))
        .歩行を遷移する(&旅行者の意図::静止, &広場.歩行の規則を組む(歩行の規則::標準()), 経過(1.0))
        .expect("区域の中の遷移は成功するべきである");
    assert_eq!(
        結果,
        遷移成功結果 {
            次の状態: 広場.広場の居場所(現在地(5.0, 5.0)),
            出来事一覧: vec![]
        }
    );
}

#[test]
fn 歩行遷移計算_壁に突き当たると境目で止まり障害物に遮られた出来事が発行される() {
    let 広場 = 東に壁のある広場();
    // 8.0mから3.0m/sで1秒歩くと11.0mになるが、東の境目10.0mで止まる
    let 結果 = 広場
        .広場の居場所(現在地(8.0, 0.0))
        .歩行を遷移する(&旅行者の意図::歩く { 方向: 歩行方向::東() }, &広場.歩行の規則を組む(歩行の規則::標準()), 経過(1.0))
        .expect("区域の中の遷移は成功するべきである");
    assert_eq!(現在地の表記(&結果.次の状態.現在地()), "東10, 北0");
    assert_eq!(結果.出来事一覧, vec![旅行者の出来事::障害物に遮られた]);
}

#[test]
fn 歩行遷移計算_境界の内側に収まる歩行では出来事は無い() {
    let 広場 = 東に壁のある広場();
    let 結果 = 広場
        .広場の居場所(現在地(2.0, 0.0))
        .歩行を遷移する(&旅行者の意図::歩く { 方向: 歩行方向::東() }, &広場.歩行の規則を組む(歩行の規則::標準()), 経過(1.0))
        .expect("区域の中の遷移は成功するべきである");
    assert_eq!(
        結果,
        遷移成功結果 {
            次の状態: 広場.広場の居場所(現在地(5.0, 0.0)),
            出来事一覧: vec![]
        }
    );
}

#[test]
fn 描画射影_居場所の現在地から描画用位置dtoを正確に取り出せる() {
    let 描画位置 = 広い広場().広場の居場所(現在地(12.5, 8.0)).描画位置を射影する();
    assert_eq!(描画位置.東メートル, メートル::生成する(12.5));
    assert_eq!(描画位置.北メートル, メートル::生成する(8.0));
}

// 現在地を「東x, 北y」と表記する。境目で止まった点が単精度の丸めで境目からずれていないかを、値そのもので見るために使う。
fn 現在地の表記(現在地: &旅行者の現在地) -> String {
    format!("東{}, 北{}", 現在地.東().値(), 現在地.北().値())
}
