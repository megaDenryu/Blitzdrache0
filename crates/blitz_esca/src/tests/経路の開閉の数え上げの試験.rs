//! 「閉じている経路は、いつも地図にある経路である」を、小さな地図の全状態・全コマンドの有限全数の検証で確かめる試験(Issue #187 の作業G1)。
//!
//! 命題は、地図の外の経路(隠し道)を含む閉じている経路の集合のそれぞれについて、その状態が到達可能でないことの連言である。
//! 状態に入りうる経路は、初期状態の地図の経路と、コマンドが指す地図の経路と隠し道だけである。状態は出来事が触れた経路の集合も持つため、地図に無い経路を含む状態の名指しは、
//! 閉じている経路(隠し道と地図の経路の部分集合、16通り)と出来事が触れた経路(地図の経路の部分集合、16通り)の組の256件で尽きる。出来事が触れた経路に隠し道が入らないのは、隠し道を指す命令が必ず失敗するためである。
//! 網羅性が全件を数え上げたであるときだけ、到達可能でないことが反証済み(したがって否定が証明済み)で答えられる。
//! 時刻は連続量であるため、予定の来ない刻み・峠道が閉じる時刻が来る刻み・開く時刻が来る刻みの3つの領域で同じ命題を確かめる。

#![allow(clippy::expect_used)]

use blitz_design_verification::{原子命題, 命題, 命題の検証器, 探索の上限, 数え上げの網羅性, 有限全数の検証器, 設計概念への参照, 項, 領域から遷移モデルを組む};

use super::地点と経路の試料::{刻み, 峠道が閉じる秒, 峠道が開く秒};
use super::経路の開閉の数え上げ::{経路の開閉の状態を名指す, 経路の開閉を数え上げる領域};

fn 確かめる刻みの領域一覧() -> Vec<経路の開閉を数え上げる領域> {
    [刻み(0.0, 1.0), 刻み(峠道が閉じる秒, 1.0), 刻み(峠道が開く秒, 1.0)].into_iter().map(経路の開閉を数え上げる領域::刻みを決めて生成する).collect()
}

// 地図の外の経路を含む閉じている経路の集合を、状態の名指しと同じ表記(識別子の順の並び)で名指す。
fn 地図の外の経路を含む状態の名指し一覧(領域: &経路の開閉を数え上げる領域) -> Vec<設計概念への参照> {
    let mut 名指し一覧 = Vec::new();
    for mut 閉じている in 領域.地図の経路の部分集合一覧() {
        閉じている.push(領域.地図の外の経路().clone());
        閉じている.sort();
        for 触れた in 領域.地図の経路の部分集合一覧() {
            名指し一覧.push(経路の開閉の状態を名指す(閉じている.iter(), 触れた.iter()));
        }
    }
    名指し一覧
}

fn 閉じている経路はいつも地図にある経路である命題を組む(領域: &経路の開閉を数え上げる領域) -> 命題 {
    let 項一覧 = 地図の外の経路を含む状態の名指し一覧(領域)
        .into_iter()
        .map(|名指し| 命題::原子から組む(原子命題::到達可能である { 状態: 項::名指した概念(名指し) }).否定する())
        .collect();
    命題::連言を組む(項一覧).expect("地図の部分集合は空集合を含むため、項は1件以上ある")
}

fn 検証器を組む(領域: &経路の開閉を数え上げる領域) -> 有限全数の検証器 {
    有限全数の検証器::生成する(領域から遷移モデルを組む(領域, 探索の上限::default()).unwrap_or_else(|食い違い| panic!("{食い違い}")))
}

#[test]
fn 経路の開閉の数え上げは全件を数え上げたと答える() {
    for 領域 in 確かめる刻みの領域一覧() {
        let 網羅性 = 領域から遷移モデルを組む(&領域, 探索の上限::default()).unwrap_or_else(|食い違い| panic!("{食い違い}")).網羅性;
        assert_eq!(網羅性, 数え上げの網羅性::全件を数え上げた, "{}", 網羅性.表記());
    }
}

#[test]
fn 閉じている経路はいつも地図にある経路であることが全状態で証明済みになる() {
    for 領域 in 確かめる刻みの領域一覧() {
        let 結果 = 検証器を組む(&領域).検証する(&閉じている経路はいつも地図にある経路である命題を組む(&領域));
        assert!(結果.証明済みか(), "{}", 結果.表記());
    }
}

#[test]
fn 探索は地図の外の経路を指す命令を実際に試し失敗した遷移として記録している() {
    // 命題が空虚に通らないこと(地図の外の経路を指す入力を1度も試していない探索で証明済みにならないこと)を確かめる。
    let 領域 = 確かめる刻みの領域一覧().remove(0);
    let 検証器 = 検証器を組む(&領域);
    let 地図の外の経路の表記 = 領域.地図の外の経路().表記().to_string();
    let 失敗した件数 = 検証器.遷移モデル().遷移一覧().iter().filter(|遷移| 遷移.失敗().is_some() && 遷移.入力().表記().contains(&地図の外の経路の表記)).count();
    let 到達可能な状態の件数 = 検証器.遷移モデル().到達可能な状態一覧を組む().件数();
    assert_eq!(到達可能な状態の件数, 16 * 16, "予定の来ない刻みでは、閉じている経路と出来事が触れた経路のあらゆる組へ到達するべきである");
    assert_eq!(失敗した件数, 到達可能な状態の件数 * 2, "到達可能な状態のそれぞれで、隠し道を閉じる命令と開く命令の2件が失敗するべきである");
}

#[test]
fn 地図の経路を全部閉じた状態は到達可能であり命題の否定の原子が働いている() {
    let 領域 = 確かめる刻みの領域一覧().remove(0);
    let 全部 = 領域.地図の経路の部分集合一覧().pop().expect("部分集合は1件以上ある");
    let 命題 = 命題::原子から組む(原子命題::到達可能である {
        状態: 項::名指した概念(経路の開閉の状態を名指す(全部.iter(), std::iter::empty())),
    });
    assert!(検証器を組む(&領域).検証する(&命題).証明済みか());
}
