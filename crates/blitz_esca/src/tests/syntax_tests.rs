//! オントロジーの構文解析テスト(Issue #137)。
//!
//! ソースコードのテキスト構文を走査し、オントロジー規律が文法通りに
//! 実装されているかを説明関数のメソッドチェーンを通じて機械検証する。

use super::syntax_checker::クレート構文検査;

const 全ソースコード: &[&str] = &[
    include_str!("../traveler.rs"),
    include_str!("../traveler_input.rs"),
    include_str!("../traveler_movement.rs"),
];

#[test]
fn 構文解析_mコマンドとm規則の型定義を検証する() {
    クレート構文検査::生成する(全ソースコード)
        .すべてのコマンドが列挙型であること()
        .すべての規則が構造体であること();
}

#[test]
fn 構文解析_m状態を実装する型はmdtoも実装していること() {
    クレート構文検査::生成する(全ソースコード).すべての状態がmdtoを実装していること();
}

#[test]
fn 構文解析_mdtoを実装する型は純粋データ規約を満たすこと() {
    クレート構文検査::生成する(全ソースコード).すべてのmdtoが純粋データ規約を満たすこと();
}

#[test]
fn 構文解析_mイベントを実装する型は純粋データ規約を満たすこと() {
    クレート構文検査::生成する(全ソースコード).すべてのイベントが純粋データ規約を満たすこと();
}

#[test]
fn 構文解析_m入力を実装する型はmdtoも実装していること() {
    クレート構文検査::生成する(全ソースコード).すべての入力がmdtoを実装していること();
}

#[test]
fn 構文解析_関数型エイリアスの型引数がオントロジーを満たすこと() {
    クレート構文検査::生成する(全ソースコード)
        .m遷移関数の型引数がオントロジーを満たすこと()
        .m射影関数の型引数がオントロジーを満たすこと()
        .m解釈関数の型引数がオントロジーを満たすこと();
}

#[test]
fn 構文解析_可変自己参照メソッドの不在を検証する() {
    クレート構文検査::生成する(全ソースコード).可変参照メソッドを一切含まないこと();
}
