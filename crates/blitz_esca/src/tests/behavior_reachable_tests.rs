//! 同じマスに載る2つの現在地が、到達可能な状態としても到達可能な遷移としても別の1件として残ることを固定する試験
//! (PR #177 のBlocker Bの是正)。
//!
//! 名指しが位置をマスの番号へ丸めると、探索は状態の同一性で2つを別物として辿るのに、モデルの状態と遷移の識別子は
//! 丸めた名前から組まれるため、命題の層で2つが同じ1件へ重なる。別の遷移が同じ遷移の識別子になれば、
//! 障害物に遮られたしか起きていない遷移で周囲を観察したの発生が通る。
//!
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::unwrap_used)]

use super::behavior_display::現在地の粗い表記のマスの一辺;
use super::behavior_domain::{旅行者の歩行を数え上げる領域, 東へ歩く遷移をモデルから名指す};
use super::behavior_landmark::{移動可能範囲の内側と同じマスに載る現在地, 移動可能範囲の内側の現在地};
use super::behavior_naming::旅行者の現在地を名指す;

#[test]
fn 同じマスに載る2つの現在地は到達可能な状態として2件残る() {
    let 一辺 = 現在地の粗い表記のマスの一辺::一メートル();
    let 左 = 移動可能範囲の内側の現在地();
    let 右 = 移動可能範囲の内側と同じマスに載る現在地();
    assert_eq!(一辺.現在地の表記(&左), 一辺.現在地の表記(&右), "この試験は、粗い表記が同じになる2つの現在地を題材にする");
    let 遷移モデルと網羅性 = 旅行者の歩行を数え上げる領域::生成する().遷移モデルと網羅性を組む();
    let 到達可能な状態一覧 = 遷移モデルと網羅性.モデル.到達可能な状態一覧を組む();
    assert!(到達可能な状態一覧.含むか(&旅行者の現在地を名指す(&左)), "内側の現在地が到達可能な状態に無い");
    assert!(到達可能な状態一覧.含むか(&旅行者の現在地を名指す(&右)), "同じマスに載る現在地が到達可能な状態に無い");
}

#[test]
fn 同じマスに載る2つの現在地からの東へ歩く遷移は別の遷移として量化される() {
    let 遷移モデルと網羅性 = 旅行者の歩行を数え上げる領域::生成する().遷移モデルと網羅性を組む();
    let 左の遷移 = 東へ歩く遷移をモデルから名指す(&遷移モデルと網羅性.モデル, &移動可能範囲の内側の現在地()).unwrap();
    let 右の遷移 = 東へ歩く遷移をモデルから名指す(&遷移モデルと網羅性.モデル, &移動可能範囲の内側と同じマスに載る現在地()).unwrap();
    assert_ne!(左の遷移, 右の遷移, "同じマスに載る2つの現在地からの遷移が、量化の項では同じ1件へ重なっている");
}
