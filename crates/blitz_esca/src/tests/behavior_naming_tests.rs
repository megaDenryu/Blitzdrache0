//! 名指しが単射であることを固定する試験(PR #177 のBlocker Bの是正)。
//!
//! 名指しが位置をマスの番号へ丸めていたため、同じマスに載る別の現在地が同じ参照へ写り、
//! 探索が別物として残した状態を命題の層が同じ1件として引き当てられた。丸めをやめたことを、
//! 粗い表記が同じになる2つの現在地で見る。粗い表記そのものは `behavior_display` に残っており、
//! 人が位置を読むための表示として使える。
//!
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::behavior_display::現在地の粗い表記のマスの一辺;
use super::behavior_identity::現在地のビット表現;
use super::behavior_naming::{旅行者の意図を名指す, 旅行者の現在地を名指す};
use crate::traveler::{旅行者の意図, 旅行者の現在地};
use crate::walking_direction::歩行方向;

fn 現在地(東: f32, 北: f32) -> 旅行者の現在地 {
    旅行者の現在地::生成する(メートル::生成する(東), メートル::生成する(北)).unwrap()
}

#[test]
fn 同じマスに載る2つの現在地は粗い表記が同じでも名指しが別である() {
    let 一辺 = 現在地の粗い表記のマスの一辺::一メートル();
    let 左 = 現在地(5.0, 5.0);
    let 右 = 現在地(5.2, 5.0);
    assert_eq!(一辺.現在地の表記(&左), 一辺.現在地の表記(&右), "この試験は、粗い表記が同じになる2つの現在地を題材にする");
    assert_ne!(旅行者の現在地を名指す(&左), 旅行者の現在地を名指す(&右), "粗い表記が同じ2つの現在地の名指しまで同じになっている");
}

#[test]
fn 状態の同一性が別である2つの現在地は名指しも別である() {
    let 左 = 現在地(5.0, 5.0);
    let 右 = 現在地(5.000_001, 5.0);
    assert_ne!(現在地のビット表現::現在地から写す(&左), 現在地のビット表現::現在地から写す(&右), "この試験は、状態の同一性が別である2つの現在地を題材にする");
    assert_ne!(旅行者の現在地を名指す(&左), 旅行者の現在地を名指す(&右), "探索が別物として残す2つの状態が、命題の名指しでは同じ1件へ写っている");
}

#[test]
fn 領域が試す6件の意図はどの2つも別の名指しへ写る() {
    // 歩く向きの名前を小数の桁数で丸めると、丸めの粗さが標本の刻みに追い付かなくなった時点で別のコマンドが同じ名前を持つ。
    // ビットの並びから名前を導けば、互いに等しくない意図が同じ名前へ写ることが写しの形として起こらない。
    let 意図一覧 = [
        旅行者の意図::静止,
        旅行者の意図::見回す,
        旅行者の意図::歩く { 方向: 歩行方向::東() },
        旅行者の意図::歩く { 方向: 歩行方向::西() },
        旅行者の意図::歩く { 方向: 歩行方向::北() },
        旅行者の意図::歩く { 方向: 歩行方向::南() },
    ];
    let 名指し一覧: Vec<String> = 意図一覧.iter().map(|意図| 旅行者の意図を名指す(意図).表記()).collect();
    for (添字, 名指し) in 名指し一覧.iter().enumerate() {
        assert_eq!(名指し一覧.iter().filter(|他| 他 == &名指し).count(), 1, "{添字}番目の意図と同じ名指しへ写る別の意図が在る: {名指し}");
    }
}
