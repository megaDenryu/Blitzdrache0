//! 世界の時刻・刻みの区間・閉じている時間帯・経路の開閉の予定・地図の読み取りの口の不変条件を固定する試験(Issue #187 の作業G1)。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::expect_used)]

use blitz_math::大域秒;

use super::地点と経路の試料::{刻み, 時刻, 経路を指す, 試験の地図を組む};
use crate::地点と経路::地点と経路の図式::{地点Id, 経路Id};
use crate::地点と経路::{経路の両端, 経路の開閉, 経路の開閉の予定, 経路の開閉の予定の生成の失敗, 閉じている時間帯, 閉じている時間帯の指定, 閉じている時間帯の生成の失敗};
use crate::時刻::{世界の時刻, 世界の時刻の生成の失敗};

fn 時間帯(始まりの秒数: f64, 終わりの秒数: f64) -> 閉じている時間帯 {
    閉じている時間帯の指定 {
        始まり: 時刻(始まりの秒数),
        終わり: 時刻(終わりの秒数),
    }
    .検証する()
    .expect("始まりが終わりより前の時間帯は検証を通るべきである")
}

#[test]
fn 世界の時刻は負と数値でない値を拒み0を受け入れる() {
    assert_eq!(世界の時刻::生成する(大域秒::生成する(0.0)), Ok(世界の時刻::世界の始まり()));
    for 値 in [-1.0, f64::NAN, f64::INFINITY] {
        let 失敗 = 世界の時刻::生成する(大域秒::生成する(値)).expect_err("負・NaN・無限大の世界の時刻は拒まれるべきである");
        assert!(matches!(失敗, 世界の時刻の生成の失敗::有限な0以上の数値でない { .. }));
    }
}

#[test]
fn 刻みは始まりの時刻を覆い経過時間だけ進んだ時刻を覆わない() {
    let パラメータ = 刻み(10.0, 1.0);
    assert!(パラメータ.その時刻がこの刻みに来るか(時刻(10.0)));
    assert!(パラメータ.その時刻がこの刻みに来るか(時刻(10.5)));
    assert!(!パラメータ.その時刻がこの刻みに来るか(時刻(11.0)), "隣の刻みと同じ時刻を2回数える");
    assert!(!パラメータ.その時刻がこの刻みに来るか(時刻(9.5)));
    assert!(!刻み(10.0, 0.0).その時刻がこの刻みに来るか(時刻(10.0)), "経過時間0の刻みが時刻を覆った");
}

#[test]
fn 閉じている時間帯は始まりが終わりより前でなければ拒まれる() {
    for (始まり, 終わり) in [(5.0, 5.0), (6.0, 5.0)] {
        let 失敗 = 閉じている時間帯の指定 {
            始まり: 時刻(始まり), 終わり: 時刻(終わり)
        }
        .検証する()
        .expect_err("始まりが終わりより前でない時間帯は拒まれるべきである");
        assert!(matches!(失敗, 閉じている時間帯の生成の失敗::始まりが終わりより前でない { .. }));
    }
}

#[test]
fn 経路の開閉の予定は重なる時間帯を拒み接する時間帯を受け入れる() {
    let 失敗 = 経路の開閉の予定::生成する(経路の開閉::開いている, vec![時間帯(0.0, 10.0), 時間帯(5.0, 20.0)]).expect_err("重なる時間帯は拒まれるべきである");
    assert!(matches!(失敗, 経路の開閉の予定の生成の失敗::時間帯が時刻の順に並んでいない { .. }));
    let 接する = 経路の開閉の予定::生成する(経路の開閉::開いている, vec![時間帯(0.0, 10.0), 時間帯(10.0, 20.0)]).expect("接する時間帯は受け入れるべきである");
    let 変化一覧: Vec<経路の開閉> = 接する.この刻みに来る変化一覧(刻み(10.0, 1.0)).collect();
    assert_eq!(変化一覧, vec![経路の開閉::開いている, 経路の開閉::閉じている], "接する時刻の変化が時刻の順(開いてから閉じる)に並んでいない");
}

#[test]
fn 地図は自分の中に在る地点と経路だけを確かめ経路の両端を答える() {
    let 地図 = 試験の地図を組む();
    assert!(地図.経路を確かめる(&経路Id("抜け穴".to_string())).is_none());
    assert!(地図.地点を確かめる(&地点Id("都".to_string())).is_none());
    let 村 = 地図.地点を確かめる(&地点Id("村".to_string())).expect("村は試験の地図に在る");
    let 峠 = 地図.地点を確かめる(&地点Id("峠".to_string())).expect("峠は試験の地図に在る");
    let 両端 = 地図.経路の両端を求める(&経路を指す(&地図, "峠道")).expect("峠道は試験の地図に在る");
    assert!(
        両端 == 経路の両端 {
            一方の地点: 村.clone(),
            もう一方の地点: 峠.clone()
        } || 両端
            == 経路の両端 {
                一方の地点: 峠, もう一方の地点: 村
            }
    );
    assert_eq!(地図.経路の識別子一覧().len(), 5);
    assert_eq!(地図.封鎖できる経路の識別子一覧().len(), 4, "脇道の抜け道は封鎖できる経路に数えない");
}
