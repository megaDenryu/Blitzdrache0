//! 経路の開閉の実物の遷移関数に当てる、有限に数え上げられる領域(Issue #187 の作業G1)。
//!
//! 領域は、試験の地図を持つ規則と、1つの遷移パラメータと、地図に無い経路(隠し道)を指す識別子をフィールドで持つ。
//! 初期状態は地図の封鎖できる4本の経路のあらゆる部分集合(16件。出来事が触れた経路は無い)であり、コマンドは命令が無いと、封鎖できる4本と隠し道のそれぞれを閉じる・開くの、あわせて11件である。
//! 封鎖できない抜け道を閉じる命令は型の上で作れないため、コマンドに入らない。
//! どちらも取りうる値を全部並べるため、網羅性は全件を数え上げたで返る。遷移パラメータは領域ごとに1つに固定する(歩行の領域が規則を固定するのと同じ)。
//! 時刻は連続量であるため、刻みを変えた領域をいくつか組んで、予定の来ない刻み・閉じる時刻が来る刻み・開く時刻が来る刻みをそれぞれ全件で確かめる。
//!
//! `一回遷移する` は `経路の開閉の状態::開閉を遷移する` をそのまま呼び、遷移の意味を試験の側へ書き写さない(Issue #173 が禁じた形)。
//! 失敗のときは、遷移失敗結果の元の状態をそのまま帰結へ入れる。元の状態が受け取った状態と等しいかは探索が確かめ、食い違えば遷移モデルを返さない(設計オントロジー 3.5.9)。

#![allow(clippy::expect_used)]

use blitz_design_verification::{数え上げ, 有限に数え上げられる領域, 設計概念への参照, 遷移の帰結};

use super::地点と経路の試料::{地図の外の経路, 試験の地図を組む};
use crate::transition_parameter::遷移パラメータ;
use crate::地点と経路::{封鎖できる経路の識別子, 経路の開閉の出来事, 経路の開閉の命令, 経路の開閉の状態, 経路の開閉の状態の指定, 経路の開閉の規則};

// 名指しが使う名前の空間。経路の開閉の型が居るモジュールを表す。
const 経路の開閉の名前の空間: &str = "blitz_esca::地点と経路";

/// 実物の遷移関数 `経路の開閉の状態::開閉を遷移する` を呼ぶ領域。
pub struct 経路の開閉を数え上げる領域 {
    規則: 経路の開閉の規則,
    パラメータ: 遷移パラメータ,
    地図の外の経路: 封鎖できる経路の識別子,
}

impl 経路の開閉を数え上げる領域 {
    /// 試験の地図と、与えた刻みの遷移パラメータで領域を組む。
    pub fn 刻みを決めて生成する(パラメータ: 遷移パラメータ) -> Self {
        Self {
            規則: 経路の開閉の規則::生成する(試験の地図を組む()),
            パラメータ,
            地図の外の経路: 地図の外の経路(),
        }
    }

    /// 地図に無い経路(隠し道)を指す識別子。命題が、地図の外の経路を含む状態を名指すために使う。
    pub fn 地図の外の経路(&self) -> &封鎖できる経路の識別子 {
        &self.地図の外の経路
    }

    /// 地図の封鎖できる経路の識別子の、あらゆる部分集合を並べる。部分集合の番号の各ビットが、地図の封鎖できる経路を識別子の順に選ぶかどうかを表す。
    /// 封鎖できない経路(抜け道)は開閉の状態にも命令にも入らないため、部分集合に数えない。
    pub fn 地図の経路の部分集合一覧(&self) -> Vec<Vec<封鎖できる経路の識別子>> {
        let 地図の経路 = self.規則.地図().封鎖できる経路の識別子一覧();
        let mut 部分集合一覧 = Vec::new();
        for 選び方 in 0..(1usize << 地図の経路.len()) {
            let 選んだ経路 = 地図の経路.iter().enumerate().filter(|(番号, _)| 選び方 & (1usize << 番号) != 0).map(|(_, 経路)| 経路.clone());
            部分集合一覧.push(選んだ経路.collect());
        }
        部分集合一覧
    }
}

/// 閉じている経路の並びと出来事が触れた経路の並びから状態を名指す。状態の名指しと、地図の外の経路を含む作れない状態の名指しが、同じ表記を使うために1箇所に置く。
/// 出来事が触れた経路も名前へ入れるのは、閉じている経路が同じで出来事が触れた経路だけが違う2つの状態を、別の名指しへ写すためである。
pub fn 経路の開閉の状態を名指す<'a>(
    閉じている経路: impl Iterator<Item = &'a 封鎖できる経路の識別子>, 出来事が触れた経路: impl Iterator<Item = &'a 封鎖できる経路の識別子>
) -> 設計概念への参照 {
    let 並べる = |並び: Vec<&str>| 並び.join("・");
    let 閉じている = 並べる(閉じている経路.map(封鎖できる経路の識別子::表記).collect());
    let 触れた = 並べる(出来事が触れた経路.map(封鎖できる経路の識別子::表記).collect());
    設計概念への参照::実行時のドメイン概念として生成する(経路の開閉の名前の空間, &format!("経路の開閉の状態(閉じている経路: {閉じている} / 出来事が触れた経路: {触れた})"))
}

impl 有限に数え上げられる領域 for 経路の開閉を数え上げる領域 {
    type 状態 = 経路の開閉の状態;
    type コマンド = 経路の開閉の命令;
    type 出来事 = 経路の開閉の出来事;
    type 状態の同一性 = 経路の開閉の状態;

    fn 初期状態を数え上げる(&self) -> 数え上げ<経路の開閉の状態> {
        数え上げ::全件(
            self.地図の経路の部分集合一覧()
                .into_iter()
                .map(|部分集合| {
                    let 指定 = 経路の開閉の状態の指定 {
                        閉じている経路: 部分集合,
                        出来事が触れた経路: Vec::new(),
                    };
                    self.規則.指定を地図で確かめて状態を作る(指定).expect("地図の経路だけの部分集合は状態になるべきである")
                })
                .collect(),
        )
    }

    fn 状態で試すコマンドを数え上げる(&self, _状態: &経路の開閉の状態) -> 数え上げ<経路の開閉の命令> {
        let mut 経路一覧 = self.規則.地図().封鎖できる経路の識別子一覧();
        経路一覧.push(self.地図の外の経路.clone());
        let 開閉の命令 = 経路一覧.into_iter().flat_map(|経路| [経路の開閉の命令::経路を閉じる { 経路: 経路.clone() }, 経路の開閉の命令::経路を開く { 経路 }]);
        数え上げ::全件(std::iter::once(経路の開閉の命令::命令が無い).chain(開閉の命令).collect())
    }

    /// 実物の遷移関数を呼ぶ。探索がたどった前の状態を覚えておけるよう、検証の側だけが複製を作って渡す。
    fn 一回遷移する(&self, 状態: &経路の開閉の状態, コマンド: &経路の開閉の命令) -> 遷移の帰結<経路の開閉の状態, 経路の開閉の出来事> {
        match 状態.clone().開閉を遷移する(コマンド, &self.規則, self.パラメータ) {
            Ok(成功) => 遷移の帰結::成功 {
                次の状態: 成功.次の状態,
                出来事一覧: 成功.出来事一覧,
            },
            Err(失敗) => 遷移の帰結::失敗 {
                元の状態: 失敗.元の状態,
                説明: 失敗.失敗の理由.to_string(),
            },
        }
    }

    fn 状態の同一性を答える(&self, 状態: &経路の開閉の状態) -> 経路の開閉の状態 {
        状態.clone()
    }

    fn 状態を名指す(&self, 状態: &経路の開閉の状態) -> 設計概念への参照 {
        経路の開閉の状態を名指す(状態.閉じている経路一覧(), 状態.出来事が触れた経路一覧())
    }

    fn コマンドを名指す(&self, コマンド: &経路の開閉の命令) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(経路の開閉の名前の空間, &format!("経路の開閉の命令({コマンド:?})"))
    }

    fn 出来事を名指す(&self, 出来事: &経路の開閉の出来事) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(経路の開閉の名前の空間, &format!("経路の開閉の出来事({出来事:?})"))
    }

    fn 規則を名指す(&self) -> 設計概念への参照 {
        設計概念への参照::実行時のドメイン概念として生成する(経路の開閉の名前の空間, "経路の開閉の規則")
    }
}
