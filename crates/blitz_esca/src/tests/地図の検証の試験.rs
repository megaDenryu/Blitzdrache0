//! 地図の検証が区域と通り口と経路の種類の食い違いを拒むことと、封鎖できない経路を閉じる命令が型の上で作れないことを固定する試験(Issue #187 の作業G2)。
//!
//! 反例は5つである。(1) 区域どうしの内部の重なり。(2) 隙間になる、共有する辺の頂点の食い違い(隣の区域が境目から少し離れている)。
//! (3) 同じ区域の同じ辺を使う2本の経路の通り口。(4) はじめから閉じた予定を持つ封鎖できない経路(脇道)。
//! (5) 封鎖できない経路(抜け道)は封鎖できる経路の識別子にならない。開閉の命令は封鎖できる経路の識別子でしか経路を指せないため、抜け道を閉じる命令は型の上で作れない。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::expect_used)]

use super::地点と経路の試料::{区域の一辺, 東の真ん中の辺, 正方形の区域, 経路を指す, 西の真ん中の辺, 試験の地図を組む, 通り口};
use crate::地点と経路::地点と経路の図式::Graph;
use crate::地点と経路::{区域, 地図の生成の失敗, 地点, 地点と経路のグラフ, 地点と経路の図式, 経路の種類, 経路の積み荷, 経路の開閉, 経路の開閉の予定};

// 2つの地点(西と東)を、与えた区域と、与えた積み荷を持つ経路でつないだグラフ。
fn 二つの地点のグラフ(西の区域: 区域, 東の区域: 区域, 積み荷一覧: Vec<経路の積み荷>) -> Graph {
    Graph::create(|組み立て| {
        let 西 = 組み立て.insert("西", 地点::区域で生成する(西の区域));
        let 東 = 組み立て.insert("東", 地点::区域で生成する(東の区域));
        for (番号, 積み荷) in 積み荷一覧.into_iter().enumerate() {
            組み立て.add(format!("経路{番号}"), 地点と経路の図式::経路::new(西.clone(), 東.clone(), 積み荷));
        }
    })
    .expect("多重度の制約を持たない図式の地図は組めるべきである")
}

fn 峠道の積み荷(種類: 経路の種類) -> 経路の積み荷 {
    経路の積み荷::生成する(種類, 通り口(東の真ん中の辺, 西の真ん中の辺), 経路の開閉の予定::時間帯を持たない(経路の開閉::開いている))
}

#[test]
fn 反例1_内部が重なる区域は拒まれる() {
    let グラフ = 二つの地点のグラフ(正方形の区域(0.0, 0.0), 正方形の区域(5.0, 0.0), vec![]);
    assert!(matches!(地点と経路のグラフ::検証して生成する(グラフ), Err(地図の生成の失敗::区域の内部が重なっている { .. })));
}

#[test]
fn 反例2_共有する辺の頂点が食い違う隙間のある区域の通り口は拒まれる() {
    // 東の区域を1センチメートルだけ東へずらし、2つの区域のあいだに隙間を作る。境目の頂点が完全に一致しないため、通り口は共有する辺にならない。
    let グラフ = 二つの地点のグラフ(正方形の区域(0.0, 0.0), 正方形の区域(区域の一辺 + 0.01, 0.0), vec![峠道の積み荷(経路の種類::門)]);
    assert!(matches!(地点と経路のグラフ::検証して生成する(グラフ), Err(地図の生成の失敗::通り口の辺が両端の区域に共有されていない { .. })));
}

#[test]
fn 反例3_同じ区域の同じ辺を使う2本の経路の通り口は拒まれる() {
    let グラフ = 二つの地点のグラフ(正方形の区域(0.0, 0.0), 正方形の区域(区域の一辺, 0.0), vec![峠道の積み荷(経路の種類::門), 峠道の積み荷(経路の種類::橋)]);
    assert!(matches!(地点と経路のグラフ::検証して生成する(グラフ), Err(地図の生成の失敗::通り口どうしが重なっている { .. })));
}

#[test]
fn 反例4_はじめから閉じた予定を持つ封鎖できない経路は拒まれる() {
    let 閉じた脇道 = 経路の積み荷::生成する(経路の種類::脇道, 通り口(東の真ん中の辺, 西の真ん中の辺), 経路の開閉の予定::時間帯を持たない(経路の開閉::閉じている));
    let グラフ = 二つの地点のグラフ(正方形の区域(0.0, 0.0), 正方形の区域(区域の一辺, 0.0), vec![閉じた脇道]);
    assert!(matches!(地点と経路のグラフ::検証して生成する(グラフ), Err(地図の生成の失敗::封鎖できない経路が閉じる予定を持つ { 種類: 経路の種類::脇道, .. })));
}

#[test]
fn 反例5_封鎖できない経路は封鎖できる経路の識別子にならず閉じる命令を作れない() {
    let 地図 = 試験の地図を組む();
    assert_eq!(地図.封鎖できる経路として確かめる(&経路を指す(&地図, "抜け道")), None, "脇道の抜け道が封鎖できる経路の識別子になった");
    assert!(地図.封鎖できる経路として確かめる(&経路を指す(&地図, "峠道")).is_some(), "幹線道路の峠道は封鎖できる経路の識別子になるべきである");
    for 種類 in [経路の種類::脇道, 経路の種類::山道] {
        assert!(!種類.封鎖できるか());
    }
    for 種類 in [経路の種類::幹線道路, 経路の種類::橋, 経路の種類::門] {
        assert!(種類.封鎖できるか());
    }
}

#[test]
fn 辺を共有して隣り合う区域と通り口は検証を通る() {
    let グラフ = 二つの地点のグラフ(正方形の区域(0.0, 0.0), 正方形の区域(区域の一辺, 0.0), vec![峠道の積み荷(経路の種類::門)]);
    let 地図 = 地点と経路のグラフ::検証して生成する(グラフ).expect("隣り合う正方形と共有する辺の通り口は検証を通るべきである");
    assert_eq!(地図.通り口一覧().len(), 1);
}
