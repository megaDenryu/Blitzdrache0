//! 旅行者の現在地と歩行の規則の生成の口が固定する不変条件のテスト(Issue #137)。座標と速さが有限な数値であることと、遷移が有限性を破る前に失敗を返し、
//! そのとき受け取った居場所を遷移失敗結果に入れてそのまま返すことと、区域の外にいる居場所の遷移が失敗することを確かめる(Issue #187 の作業G2)。

#![allow(clippy::expect_used)]

