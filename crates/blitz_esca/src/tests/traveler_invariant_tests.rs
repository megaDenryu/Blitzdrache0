//! 旅行者の現在地と歩行の規則の生成の口が固定する不変条件のテスト(Issue #137)。座標と速さが有限な数値であることと、遷移が有限性を破る前に失敗を返し、
//! そのとき受け取った現在地を遷移失敗結果に入れてそのまま返すことを確かめる。

#![allow(clippy::expect_used)]

use blitz_math::{メートル, メートル毎秒, 秒};

use crate::elapsed_time::経過時間;
use crate::ontology::M遷移関数;
use crate::transition_parameter::遷移パラメータ;
use crate::traveler::{旅行者の出来事, 旅行者の意図, 旅行者の現在地, 歩行の規則};
use crate::traveler_error::{旅行者の現在地の生成の失敗, 歩行の規則の生成の失敗};
use crate::traveler_movement::歩行遷移の規則;
use crate::walking_direction::歩行方向;

#[test]
fn 歩行の規則_速さは有限な0以上の数値だけを受け入れる() {
    let 零 = 歩行の規則::生成する(メートル毎秒::生成する(0.0)).expect("速さ0は静止と矛盾しないため受け入れるべきである");
    assert_eq!(零.速さ(), メートル毎秒::生成する(0.0));
    for 値 in [-1.0, f32::NAN, f32::INFINITY, f32::NEG_INFINITY] {
        let 失敗 = 歩行の規則::生成する(メートル毎秒::生成する(値)).expect_err("負・NaN・無限大の速さは拒まれるべきである");
        assert!(matches!(失敗, 歩行の規則の生成の失敗::速さが有限な0以上の数値でない { .. }));
    }
}

#[test]
fn 現在地_nanと無限大の座標は拒まれる() {
    for 値 in [f32::NAN, f32::INFINITY, f32::NEG_INFINITY] {
        let 東が壊れた = 旅行者の現在地::生成する(メートル::生成する(値), メートル::生成する(0.0)).expect_err("NaN・無限大の東は拒まれるべきである");
        assert!(matches!(東が壊れた, 旅行者の現在地の生成の失敗::座標が有限な数値でない { .. }));
        let 北が壊れた = 旅行者の現在地::生成する(メートル::生成する(0.0), メートル::生成する(値)).expect_err("NaN・無限大の北は拒まれるべきである");
        assert!(matches!(北が壊れた, 旅行者の現在地の生成の失敗::座標が有限な数値でない { .. }));
    }
}

// 速さが f32::MAX の規則。有限な速さと経過時間の積が表現範囲を超える遷移を作るために使う。
fn 表現範囲を超える速さの規則() -> 歩行遷移の規則 {
    歩行遷移の規則::制約なし(歩行の規則::生成する(メートル毎秒::生成する(f32::MAX)).expect("f32::MAX は有限であるため規則になるべきである"))
}

fn 二秒の遷移パラメータ() -> 遷移パラメータ {
    遷移パラメータ {
        経過時間: 経過時間::生成する(秒::生成する(2.0)).expect("2秒は経過時間になるべきである"),
    }
}

#[test]
fn 歩行遷移_有限な速さと経過時間の積が表現範囲を超えると遷移は失敗を返し受け取った現在地をそのまま返す() {
    let 現在地 = 旅行者の現在地::生成する(メートル::生成する(1.5), メートル::生成する(-2.5)).expect("有限な座標は現在地になるべきである");
    let 失敗 = 現在地
        .歩行を遷移する(&旅行者の意図::歩く { 方向: 歩行方向::東() }, &表現範囲を超える速さの規則(), 二秒の遷移パラメータ())
        .expect_err("東の座標が無限大になる遷移は失敗を返すべきである");
    assert!(matches!(失敗.失敗の理由, 旅行者の現在地の生成の失敗::座標が有限な数値でない { .. }));
    assert_eq!(失敗.元の状態, 現在地, "失敗した遷移は受け取った現在地を変えずに返すべきである");
}

#[test]
fn 遷移関数の役割_包んだ遷移が失敗すると渡した状態が遷移失敗結果に入って戻る() {
    let 遷移: M遷移関数<旅行者の現在地, 旅行者の意図, 歩行遷移の規則, 旅行者の出来事, 旅行者の現在地の生成の失敗> = M遷移関数::生成する(旅行者の現在地::歩行を遷移する);
    let 現在地 = 旅行者の現在地::生成する(メートル::生成する(-4.0), メートル::生成する(7.0)).expect("有限な座標は現在地になるべきである");
    let 失敗 = 遷移
        .呼び出す(現在地, &旅行者の意図::歩く { 方向: 歩行方向::北() }, &表現範囲を超える速さの規則(), 二秒の遷移パラメータ())
        .expect_err("北の座標が無限大になる遷移は失敗を返すべきである");
    assert_eq!(失敗.元の状態, 現在地, "役割を通して呼んでも、失敗した遷移は渡した状態を変えずに返すべきである");
}
