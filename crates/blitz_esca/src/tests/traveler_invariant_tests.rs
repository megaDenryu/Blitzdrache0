//! 旅行者の現在地と歩行の規則の生成の口が固定する不変条件のテスト(Issue #137)。座標と速さが有限な数値であることを確かめる。
//! 歩行の状態遷移は失敗しない。状態遷移の中で有限性が破れることと、区域の外にいる居場所を状態遷移させることは、プログラムの誤りとして状態遷移が停止することを確かめる
//! (Issue #187 の作業G2。2026-09-28 オーナー裁定。設計オントロジー 3.5.9)。

#![allow(clippy::expect_used)]

use std::convert::Infallible;

use blitz_design::M状態遷移関数;
use blitz_math::{メートル, メートル毎秒};

use super::一つの区域の試料::{現在地, 経過, 長方形の端};
use crate::transition_parameter::状態遷移パラメータ;
use crate::traveler_error::{旅行者の現在地の生成の失敗, 歩行の規則の生成の失敗};
use crate::walking_direction::歩行方向;
use crate::居場所::旅行者の居場所;
use crate::旅行者::{旅行者の出来事, 旅行者の意図, 旅行者の現在地, 歩行の規則};
use crate::歩行の状態遷移::歩行の状態遷移の規則;

#[test]
fn 歩行の規則_速さは有限な0以上の数値だけを受け入れる() {
    let 零 = 歩行の規則::生成する(メートル毎秒::生成する(0.0)).expect("速さ0は静止と矛盾しないため受け入れるべきである");
    assert_eq!(零.速さ(), メートル毎秒::生成する(0.0));
    for 値 in [-1.0, f32::NAN, f32::INFINITY, f32::NEG_INFINITY] {
        let 失敗 = 歩行の規則::生成する(メートル毎秒::生成する(値)).expect_err("負・NaN・無限大の速さは拒まれるべきである");
        assert!(matches!(失敗, 歩行の規則の生成の失敗::速さが有限な0以上の数値でない { .. }));
    }
}

#[test]
fn 現在地_nanと無限大の座標は拒まれる() {
    for 値 in [f32::NAN, f32::INFINITY, f32::NEG_INFINITY] {
        let 東が壊れた = 旅行者の現在地::生成する(メートル::生成する(値), メートル::生成する(0.0)).expect_err("NaN・無限大の東は拒まれるべきである");
        assert!(matches!(東が壊れた, 旅行者の現在地の生成の失敗::座標が有限な数値でない { .. }));
        let 北が壊れた = 旅行者の現在地::生成する(メートル::生成する(0.0), メートル::生成する(値)).expect_err("NaN・無限大の北は拒まれるべきである");
        assert!(matches!(北が壊れた, 旅行者の現在地の生成の失敗::座標が有限な数値でない { .. }));
    }
}

// 境界に届かない、東西と南北に2000メートルの広場。
fn 広い広場() -> 長方形の端 {
    長方形の端 {
        東の最小: -1000.0,
        東の最大: 1000.0,
        北の最小: -1000.0,
        北の最大: 1000.0,
    }
}

// 速さが f32::MAX の規則。有限な速さと経過時間の積が表現範囲を超える状態遷移を作るために使う。
fn 表現範囲を超える速さの規則() -> 歩行の状態遷移の規則 {
    広い広場().歩行の規則を組む(歩行の規則::生成する(メートル毎秒::生成する(f32::MAX)).expect("f32::MAX は有限であるため規則になるべきである"))
}

#[test]
#[should_panic(expected = "歩いた先の現在地が有限な数でなくなった")]
fn 歩行の状態遷移_有限な速さと経過時間の積が表現範囲を超えると状態遷移はプログラムの誤りとして停止する() {
    let 居場所 = 広い広場().広場の居場所(現在地(1.5, -2.5));
    let _ = 居場所.歩行を状態遷移させる(&旅行者の意図::歩く { 方向: 歩行方向::東() }, &表現範囲を超える速さの規則(), 経過(2.0));
}

#[test]
fn 状態遷移関数の役割_失敗しない状態遷移を役割を通して呼ぶと次の居場所を返す() {
    let 状態遷移: M状態遷移関数<旅行者の居場所, 旅行者の意図, 歩行の状態遷移の規則, 状態遷移パラメータ, 旅行者の出来事, Infallible> = M状態遷移関数::生成する(旅行者の居場所::歩行を状態遷移させる);
    let 規則 = 広い広場().歩行の規則を組む(歩行の規則::生成する(メートル毎秒::生成する(2.0)).expect("有限な正の速さは規則になるべきである"));
    let 成功 = match 状態遷移.呼び出す(広い広場().広場の居場所(現在地(-4.0, 7.0)), &旅行者の意図::歩く { 方向: 歩行方向::北() }, &規則, 経過(1.0)) {
        Ok(成功) => 成功,
        Err(失敗) => 失敗.起こらない失敗の分岐を閉じる(),
    };
    assert_eq!(成功.次の状態(), &広い広場().広場の居場所(現在地(-4.0, 9.0)), "役割を通して呼んでも、歩行は速さと経過時間だけ北へ進むべきである");
}

// 東西と南北に10メートルの広場。
fn 小さな広場() -> 長方形の端 {
    長方形の端 {
        東の最小: 0.0,
        東の最大: 10.0,
        北の最小: 0.0,
        北の最大: 10.0,
    }
}

// 小さな広場の地点にいながら、その区域の外(東に20メートル)にある居場所。
fn 区域の外の居場所() -> 旅行者の居場所 {
    小さな広場().広場の居場所(現在地(20.0, 5.0))
}

#[test]
#[should_panic(expected = "旅行者の居場所が空間制約の区域の中に無い")]
fn 歩行の状態遷移_区域の外にいる居場所を静止させる状態遷移はプログラムの誤りとして停止する() {
    let _ = 区域の外の居場所().歩行を状態遷移させる(&旅行者の意図::静止, &小さな広場().歩行の規則を組む(歩行の規則::標準()), 経過(1.0));
}

#[test]
#[should_panic(expected = "旅行者の居場所が空間制約の区域の中に無い")]
fn 歩行の状態遷移_区域の外にいる居場所を歩かせる状態遷移はプログラムの誤りとして停止する() {
    let _ = 区域の外の居場所().歩行を状態遷移させる(&旅行者の意図::歩く { 方向: 歩行方向::西() }, &小さな広場().歩行の規則を組む(歩行の規則::標準()), 経過(1.0));
}
