#[test]
fn 歩行の規則_速さは有限な0以上の数値だけを受け入れる() {
    let 零 = 歩行の規則::生成する(メートル毎秒::生成する(0.0)).expect("速さ0は静止と矛盾しないため受け入れるべきである");
    assert_eq!(零.速さ(), メートル毎秒::生成する(0.0));
    for 値 in [-1.0, f32::NAN, f32::INFINITY, f32::NEG_INFINITY] {
        let 失敗 = 歩行の規則::生成する(メートル毎秒::生成する(値)).expect_err("負・NaN・無限大の速さは拒まれるべきである");
        assert!(matches!(失敗, 歩行の規則の生成の失敗::速さが有限な0以上の数値でない { .. }));
    }
}

#[test]
fn 現在地_nanと無限大の座標は拒まれる() {
    for 値 in [f32::NAN, f32::INFINITY, f32::NEG_INFINITY] {
        let 東が壊れた = 旅行者の現在地::生成する(メートル::生成する(値), メートル::生成する(0.0)).expect_err("NaN・無限大の東は拒まれるべきである");
        assert!(matches!(東が壊れた, 旅行者の現在地の生成の失敗::座標が有限な数値でない { .. }));
        let 北が壊れた = 旅行者の現在地::生成する(メートル::生成する(0.0), メートル::生成する(値)).expect_err("NaN・無限大の北は拒まれるべきである");
        assert!(matches!(北が壊れた, 旅行者の現在地の生成の失敗::座標が有限な数値でない { .. }));
    }
}

// 境界に届かない、東西と南北に2000メートルの広場。
fn 広い広場() -> 長方形の端 {
    長方形の端 {
        東の最小: -1000.0,
        東の最大: 1000.0,
        北の最小: -1000.0,
        北の最大: 1000.0,
    }
}

// 速さが f32::MAX の規則。有限な速さと経過時間の積が表現範囲を超える遷移を作るために使う。
fn 表現範囲を超える速さの規則() -> 歩行遷移の規則 {
    広い広場().歩行の規則を組む(歩行の規則::生成する(メートル毎秒::生成する(f32::MAX)).expect("f32::MAX は有限であるため規則になるべきである"))
}

#[test]
fn 歩行遷移_有限な速さと経過時間の積が表現範囲を超えると遷移は失敗を返し受け取った居場所をそのまま返す() {
    let 居場所 = 広い広場().広場の居場所(現在地(1.5, -2.5));
    let 失敗 = 居場所
        .clone()
        .歩行を遷移する(&旅行者の意図::歩く { 方向: 歩行方向::東() }, &表現範囲を超える速さの規則(), 経過(2.0))
        .expect_err("東の座標が無限大になる遷移は失敗を返すべきである");
    assert!(matches!(失敗.失敗の理由, 歩行の失敗::現在地を作れない(旅行者の現在地の生成の失敗::座標が有限な数値でない { .. })));
    assert_eq!(失敗.元の状態, 居場所, "失敗した遷移は受け取った居場所を変えずに返すべきである");
}

#[test]
fn 遷移関数の役割_包んだ遷移が失敗すると渡した状態が遷移失敗結果に入って戻る() {
    let 遷移: M遷移関数<旅行者の居場所, 旅行者の意図, 歩行遷移の規則, 旅行者の出来事, 歩行の失敗> = M遷移関数::生成する(旅行者の居場所::歩行を遷移する);
    let 居場所 = 広い広場().広場の居場所(現在地(-4.0, 7.0));
    let 失敗 = 遷移
        .呼び出す(居場所.clone(), &旅行者の意図::歩く { 方向: 歩行方向::北() }, &表現範囲を超える速さの規則(), 経過(2.0))
        .expect_err("北の座標が無限大になる遷移は失敗を返すべきである");
    assert_eq!(失敗.元の状態, 居場所, "役割を通して呼んでも、失敗した遷移は渡した状態を変えずに返すべきである");
}

#[test]
fn 歩行遷移_区域の外にいる居場所はどの意図でも失敗し受け取った居場所をそのまま返す() {
    let 広場 = 長方形の端 {
        東の最小: 0.0,
        東の最大: 10.0,
        北の最小: 0.0,
        北の最大: 10.0,
    };
    let 世界の外 = 広場.広場の居場所(現在地(20.0, 5.0));
    for 意図 in [旅行者の意図::静止, 旅行者の意図::見回す, 旅行者の意図::歩く { 方向: 歩行方向::西() }] {
        let 失敗 = 世界の外
            .clone()
            .歩行を遷移する(&意図, &広場.歩行の規則を組む(歩行の規則::標準()), 経過(1.0))
            .expect_err("区域の外にいる居場所の遷移は失敗するべきである");
        assert!(matches!(失敗.失敗の理由, 歩行の失敗::区域の中を動けない(区域の中の移動の失敗::始点が地点の区域の外にある { .. })), "{意図:?}: {:?}", 失敗.失敗の理由);
        assert_eq!(失敗.元の状態, 世界の外);
    }
}
