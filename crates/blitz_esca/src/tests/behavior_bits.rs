//! 単精度の値を丸めずに写すビットの並び(PR #177 のBlocker Bの是正)。
//!
//! 名指しと状態の同一性はどちらもこの写しを源にする。源を1つにするのは、名指しだけが丸めていると、
//! 探索が別物として残した状態を命題の層が同じ1件として引き当てられるためである。
//! 単精度は `Eq` も `Hash` も持たないため、鍵にするにはビットの並びへ写す必要もある。
//!
//! 表記に十進の値とビットの並びの両方を書くのは、人が読めることとビットの並びが違えば表記も違うことを同時に満たすためである。
//! 十進だけでは、同じ桁数へ丸めた別の値が同じ表記になる。

/// 単精度のビットの並びとは、単精度の値を丸めずにそのまま写した32ビットの並びのことである。
/// 異なる単精度の値が同じ並びへ写ることは無い。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct 単精度のビットの並び(u32);

impl 単精度のビットの並び {
    /// 単精度の値をビットの並びへ写す。
    pub fn 値から写す(値: f32) -> Self {
        Self(値.to_bits())
    }

    /// 人が読む表記。十進の値とビットの並びを並べて書く。
    pub fn 表記(&self) -> String {
        format!("{}(ビット{:08x})", f32::from_bits(self.0), self.0)
    }
}

#[cfg(test)]
mod 単精度のビットの並びの試験 {
    use super::単精度のビットの並び;

    #[test]
    fn 小数第一位までが同じ2つの値は表記まで別である() {
        let 甲 = 単精度のビットの並び::値から写す(5.0);
        let 乙 = 単精度のビットの並び::値から写す(5.000_001);
        assert_ne!(甲, 乙, "異なる単精度の値が同じビットの並びへ写っている");
        assert_ne!(甲.表記(), 乙.表記(), "異なるビットの並びが同じ表記になっている");
    }
}
