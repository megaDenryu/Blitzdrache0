//! 旅行者の現在地を人が読むための粗い表記(PR #177 のBlocker Bの是正)。
//!
//! **ここが作るのは表示であって識別子ではない。** 位置をマスの番号へ丸めるため、同じマスに載る別の現在地は同じ表記になる。
//! この丸めを名指しへ入れてはならず、名指しは `behavior_naming` が丸めずに作る。
//! 人が位置を読むための粗い表記を捨てずに残すのは、報告の側が「どのマスに居るか」で状態を語れるようにするためである。

use blitz_math::メートル;

use crate::traveler::旅行者の現在地;

/// 現在地を粗く表記するときのマスの一辺。位置をこの一辺で割った番号が表記に入る。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 現在地の粗い表記のマスの一辺(メートル);

impl 現在地の粗い表記のマスの一辺 {
    /// 一辺が1メートルのマス。歩行の標準の速さ3メートル毎秒と1秒の経過時間の積がこの一辺の整数倍になる。
    pub fn 一メートル() -> Self {
        Self(メートル::生成する(1.0))
    }

    /// 現在地をマスの番号で書いた粗い表記。同じマスに載る2つの現在地は同じ表記になる。
    pub fn 現在地の表記(&self, 現在地: &旅行者の現在地) -> String {
        format!("旅行者の現在地(東{}マス, 北{}マス)", self.マスの番号(現在地.東()), self.マスの番号(現在地.北()))
    }

    // 位置を一辺で割って最も近い整数へ丸めた番号の表記。整数の型へ変換せず表記のうえで丸めるのは、数値の `as` キャストを規約が禁じるためである。
    fn マスの番号(&self, 位置: メートル) -> String {
        format!("{:.0}", (位置.値() / self.0.値()).round())
    }
}
