//! 旅行者の歩行の実物の遷移関数に当てる、有限に数え上げられる領域(Issue #174)。
//!
//! この型は歩行遷移の規則(身体の歩行の規則と空間制約の区域)と遷移パラメータ(経過時間)を自分のフィールドで持つ。
//! 空間制約は、東と北を0から10メートルに限る正方形の区域を1つだけ持つ地図である(第1段階の長方形の移動可能範囲を、Issue #187 の作業G2で1つの区域で表し直した)。
//! 区域が1つであるため、どの状態も同じ広場にいて、状態は現在地で決まる。
//! 有限に数え上げられる領域のトレイトがこの2つを名指さないのは、どちらも `blitz_esca` の型であり、検証のクレートがドメインを知らないためである。
//! 数え上げの実装は子モジュールに置く(CLAUDE.md「切り出しの根拠義務」の1号のトレイト実装の分離)。
//! ここが持つのは、領域そのものの組み立てと、探索の起動である。
//! 代表の現在地は領域のフィールドを1つも読まないため `behavior_landmark` が自由関数で持つ。

mod enumeration;

use blitz_design_verification::{探索が組んだ遷移モデルと網羅性, 探索の上限, 有限全数の検証器, 設計概念への参照, 遷移モデル, 領域から遷移モデルを組む};

use super::behavior_landmark::移動可能範囲の端のメートル;
use super::behavior_naming::{旅行者の意図を名指す, 旅行者の現在地を名指す};
use super::一つの区域の試料::{経過, 長方形の端};
use crate::transition_parameter::遷移パラメータ;
use crate::traveler::{旅行者の意図, 旅行者の現在地, 歩行の規則};
use crate::traveler_movement::歩行遷移の規則;
use crate::walking_direction::歩行方向;
use crate::居場所::旅行者の居場所;

// 1回の遷移に与える経過時間の秒数。標準の速さ3メートル毎秒との積が3メートルであり、移動可能範囲の端の整数分の1になる。
const 一回の遷移の秒数: f32 = 1.0;

/// 実物の遷移関数 `旅行者の居場所::歩行を遷移する` を呼ぶ領域。
pub struct 旅行者の歩行を数え上げる領域 {
    広場: 長方形の端,
    規則: 歩行遷移の規則,
    パラメータ: 遷移パラメータ,
}

impl 旅行者の歩行を数え上げる領域 {
    /// 東と北を0から10メートルへ限った正方形の区域1つと、標準の歩行の規則と、1秒の経過時間で領域を組む。
    pub fn 生成する() -> Self {
        let 広場 = 長方形の端 {
            東の最小: 0.0,
            東の最大: 移動可能範囲の端のメートル,
            北の最小: 0.0,
            北の最大: 移動可能範囲の端のメートル,
        };
        Self {
            規則: 広場.歩行の規則を組む(歩行の規則::標準()),
            パラメータ: 経過(一回の遷移の秒数),
            広場,
        }
    }

    /// 広場にいる、その現在地の居場所。
    pub fn 広場の居場所(&self, 現在地: 旅行者の現在地) -> 旅行者の居場所 {
        self.広場.広場の居場所(現在地)
    }

    /// 状態と遷移を数え上げた結果。網羅性は `連続量の標本に限る` で返る。
    pub fn 遷移モデルと網羅性を組む(&self) -> 探索が組んだ遷移モデルと網羅性 {
        領域から遷移モデルを組む(self, 探索の上限::default()).unwrap_or_else(|食い違い| panic!("{食い違い}"))
    }

    /// 数え上げた結果から命題の検証器を組む。
    pub fn 検証器を組む(&self) -> 有限全数の検証器 {
        有限全数の検証器::生成する(self.遷移モデルと網羅性を組む())
    }

    /// 探索が組んだモデルの中から、その現在地を前状態とし東へ歩く遷移1件を名指す。
    /// 遷移の識別子の表記は探索の側が決めるため、試験の側へ書き写さずモデルから取る。
    pub fn 東へ歩く遷移を名指す(&self, 現在地: &旅行者の現在地) -> Option<設計概念への参照> {
        東へ歩く遷移をモデルから名指す(&self.遷移モデルと網羅性を組む().モデル, 現在地)
    }
}

/// 到達可能な遷移の中から、その現在地を前状態とし東へ歩く遷移1件を項の参照で名指す。
/// 領域のフィールドを1つも読まないため自由関数で持つ(参照: グローバルCLAUDE.md「Rustの書き方の選択」条5(a))。
pub fn 東へ歩く遷移をモデルから名指す(モデル: &遷移モデル, 現在地: &旅行者の現在地) -> Option<設計概念への参照> {
    let 前状態 = 旅行者の現在地を名指す(現在地);
    let 入力 = 旅行者の意図を名指す(&旅行者の意図::歩く { 方向: 歩行方向::東() });
    モデル
        .到達可能な遷移一覧()
        .iter()
        .find(|候補| 候補.前状態() == &前状態 && 候補.入力() == &入力)
        .map(|見つけた| 見つけた.識別子().設計概念への参照として表す())
}
