//! 旅行者の歩行の実物の遷移関数に当てる、有限に数え上げられる領域(Issue #174)。
//!
//! この型は歩行遷移の規則(身体の歩行の規則と空間制約の移動可能範囲)と遷移パラメータ(経過時間)を自分のフィールドで持つ。
//! 有限に数え上げられる領域のトレイトがこの2つを名指さないのは、どちらも `blitz_esca` の型であり、検証のクレートがドメインを知らないためである。
//! 数え上げの実装は子モジュールに置く(CLAUDE.md「切り出しの根拠義務」の1号のトレイト実装の分離)。
//! ここが持つのは、領域そのものの組み立てと、命題が名指す代表の現在地と、探索の起動である。

#![allow(clippy::unwrap_used)]

mod enumeration;

use blitz_design_verification::{探索の上限, 探索の結末, 有限全数の検証器, 設計概念の識別子, 領域から遷移モデルを組む};
use blitz_math::{メートル, 秒};

use super::behavior_naming::{旅行者の意図を名指す, 現在地を名指すマスの一辺};
use crate::elapsed_time::経過時間;
use crate::transition_parameter::遷移パラメータ;
use crate::traveler::{旅行者の意図, 旅行者の現在地, 歩行の規則};
use crate::traveler_boundary::移動可能範囲の指定;
use crate::traveler_movement::歩行遷移の規則;
use crate::walking_direction::歩行方向;

// 移動可能範囲の東と北の最大。最小は0であり、東の端の現在地の東がこの値に載る。
const 移動可能範囲の端のメートル: f32 = 10.0;

// 1回の遷移に与える経過時間の秒数。標準の速さ3メートル毎秒との積が3メートルであり、マスの一辺の整数倍になる。
const 一回の遷移の秒数: f32 = 1.0;

/// 実物の遷移関数 `旅行者の現在地::歩行を遷移する` を呼ぶ領域。
pub struct 旅行者の歩行を数え上げる領域 {
    規則: 歩行遷移の規則,
    パラメータ: 遷移パラメータ,
    マスの一辺: 現在地を名指すマスの一辺,
}

impl 旅行者の歩行を数え上げる領域 {
    /// 東と北を0から10メートルへ限った移動可能範囲と、標準の歩行の規則と、1秒の経過時間で領域を組む。
    pub fn 生成する() -> Self {
        let 空間制約 = 移動可能範囲の指定 {
            東の最小: メートル::生成する(0.0),
            東の最大: メートル::生成する(移動可能範囲の端のメートル),
            北の最小: メートル::生成する(0.0),
            北の最大: メートル::生成する(移動可能範囲の端のメートル),
        }
        .検証する()
        .unwrap();
        Self {
            規則: 歩行遷移の規則::空間制約付き(歩行の規則::標準(), 空間制約),
            パラメータ: 遷移パラメータ {
                経過時間: 経過時間::生成する(秒::生成する(一回の遷移の秒数)).unwrap(),
            },
            マスの一辺: 現在地を名指すマスの一辺::一メートル(),
        }
    }

    /// 東の端に立つ現在地。ここから東へ歩くと移動可能範囲の外へ出ようとして境界に当たる。
    pub fn 東の端の現在地(&self) -> 旅行者の現在地 {
        self.現在地を組む(移動可能範囲の端のメートル, 5.0)
    }

    /// 移動可能範囲の内側に立つ現在地。ここから東へ歩いても範囲の外へ出ない。
    pub fn 内側の現在地(&self) -> 旅行者の現在地 {
        self.現在地を組む(5.0, 5.0)
    }

    /// 内側の現在地から東へ1回歩いた後の現在地。速さ3メートル毎秒と1秒の積だけ東へ進んだ位置である。
    pub fn 内側から東へ歩いた現在地(&self) -> 旅行者の現在地 {
        self.現在地を組む(8.0, 5.0)
    }

    /// 移動可能範囲の外に在り、どの初期状態からも到達しない現在地。
    pub fn 範囲の外の現在地(&self) -> 旅行者の現在地 {
        self.現在地を組む(20.0, 20.0)
    }

    /// 現在地を名指すマスの一辺。命題を組む工程が状態の名前をこの一辺で作る。
    pub fn マスの一辺(&self) -> 現在地を名指すマスの一辺 {
        self.マスの一辺
    }

    /// 状態と遷移を数え上げた結末。網羅性は `連続量の標本に限る` で返る。
    pub fn 探索の結末を組む(&self) -> 探索の結末 {
        領域から遷移モデルを組む(self, 探索の上限::default())
    }

    /// 数え上げた結末から命題の検証器を組む。
    pub fn 検証器を組む(&self) -> 有限全数の検証器 {
        有限全数の検証器::生成する(self.探索の結末を組む())
    }

    /// 探索が組んだモデルの中から、移動可能範囲の内側を東へ歩く遷移1件を名指す。
    /// 遷移の識別子の表記は探索の側が決めるため、試験の側へ書き写さずモデルから取る。
    pub fn 内側を東へ歩く遷移を名指す(&self) -> Option<設計概念の識別子> {
        let 前状態 = self.マスの一辺.現在地を名指す(&self.内側の現在地());
        let 入力 = 旅行者の意図を名指す(&旅行者の意図::歩く { 方向: 歩行方向::東() });
        self.探索の結末を組む()
            .モデル
            .遷移一覧()
            .iter()
            .find(|候補| 候補.前状態() == &前状態 && 候補.入力() == &入力)
            .map(|見つけた| 見つけた.識別子().設計概念の識別子として表す())
    }

    fn 現在地を組む(&self, 東: f32, 北: f32) -> 旅行者の現在地 {
        旅行者の現在地::生成する(メートル::生成する(東), メートル::生成する(北)).unwrap()
    }
}
