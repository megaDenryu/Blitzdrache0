//! 移動可能範囲の検証付き生成と境界制限のテスト(Issue #137)。

#![allow(clippy::expect_used)]

use blitz_math::メートル;

use crate::traveler::旅行者の現在地;
use crate::traveler_boundary::{移動可能範囲, 移動可能範囲の指定};
use crate::traveler_boundary_error::{移動可能範囲の生成の失敗, 移動可能範囲の軸};

fn 十メートル四方の範囲() -> 移動可能範囲 {
    移動可能範囲の指定 {
        東の最小: メートル::生成する(-10.0),
        東の最大: メートル::生成する(10.0),
        北の最小: メートル::生成する(-10.0),
        北の最大: メートル::生成する(10.0),
    }
    .検証する()
    .expect("最小が最大以下の指定は検証を通るべきである")
}

#[test]
fn 境界制限_空間内ではそのままの座標を返し衝突は偽() {
    let 目的地 = 旅行者の現在地::生成する(メートル::生成する(3.0), メートル::生成する(5.0));
    let 結果 = 十メートル四方の範囲().制限する(目的地);
    assert_eq!(結果.制限後の東, 目的地.東());
    assert_eq!(結果.制限後の北, 目的地.北());
    assert!(!結果.衝突した);
}

#[test]
fn 境界制限_範囲の外の目的地は端へ収められ衝突は真() {
    let 目的地 = 旅行者の現在地::生成する(メートル::生成する(12.0), メートル::生成する(-15.0));
    let 結果 = 十メートル四方の範囲().制限する(目的地);
    assert_eq!(結果.制限後の東, メートル::生成する(10.0));
    assert_eq!(結果.制限後の北, メートル::生成する(-10.0));
    assert!(結果.衝突した);
}

#[test]
fn 検証_最小が最大を超える指定は軸と値を添えて拒まれる() {
    let 失敗 = 移動可能範囲の指定 {
        東の最小: メートル::生成する(0.0),
        東の最大: メートル::生成する(10.0),
        北の最小: メートル::生成する(5.0),
        北の最大: メートル::生成する(-5.0),
    }
    .検証する()
    .expect_err("北の最小が最大を超える指定は拒まれるべきである");
    assert_eq!(
        失敗,
        移動可能範囲の生成の失敗::最小が最大を超えている {
            軸: 移動可能範囲の軸::南北,
            最小: メートル::生成する(5.0),
            最大: メートル::生成する(-5.0)
        }
    );
}

#[test]
fn 検証_数値でない端を持つ指定は拒まれる() {
    let 失敗 = 移動可能範囲の指定 {
        東の最小: メートル::生成する(f32::NAN),
        東の最大: メートル::生成する(10.0),
        北の最小: メートル::生成する(-10.0),
        北の最大: メートル::生成する(10.0),
    }
    .検証する()
    .expect_err("数値でない端を持つ指定は拒まれるべきである");
    assert_eq!(失敗, 移動可能範囲の生成の失敗::数値でない { 軸: 移動可能範囲の軸::東西 });
}
