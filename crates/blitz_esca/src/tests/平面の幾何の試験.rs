//! 平面の幾何(単純多角形の検証・点の位置・線分の区切り・多角形の重なり)の不変条件と反例を固定する試験(Issue #187 の作業G2)。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::expect_used)]

use blitz_math::大域メートル;

use crate::平面の幾何::{単純多角形, 単純多角形の生成の失敗, 多角形に対する位置, 平面の点, 平面の線分};

fn 点(東: f64, 北: f64) -> 平面の点 {
    平面の点 {
        東: 大域メートル::生成する(東),
        北: 大域メートル::生成する(北),
    }
}

fn 多角形(頂点一覧: &[(f64, f64)]) -> Result<単純多角形, 単純多角形の生成の失敗> {
    単純多角形::検証する(頂点一覧.iter().map(|(東, 北)| 点(*東, *北)).collect())
}

fn 正方形(南西の東: f64, 南西の北: f64, 一辺: f64) -> 単純多角形 {
    多角形(&[(南西の東, 南西の北), (南西の東 + 一辺, 南西の北), (南西の東 + 一辺, 南西の北 + 一辺), (南西の東, 南西の北 + 一辺)]).expect("反時計回りの正方形は単純多角形である")
}

#[test]
fn 頂点が3つより少ない並びと時計回りの並びと自己交差する並びは拒まれる() {
    assert_eq!(多角形(&[(0.0, 0.0), (1.0, 0.0)]), Err(単純多角形の生成の失敗::頂点が3つより少ない { 頂点の数: 2 }));
    assert_eq!(多角形(&[(0.0, 0.0), (0.0, 1.0), (1.0, 1.0), (1.0, 0.0)]), Err(単純多角形の生成の失敗::頂点が反時計回りに並んでいない));
    let 蝶ネクタイ = 多角形(&[(0.0, 0.0), (2.0, 2.0), (2.0, 0.0), (0.0, 2.0)]);
    assert!(
        matches!(蝶ネクタイ, Err(単純多角形の生成の失敗::辺どうしが触れている { .. }) | Err(単純多角形の生成の失敗::頂点が反時計回りに並んでいない)),
        "{蝶ネクタイ:?}"
    );
    let 折り返す = 多角形(&[(0.0, 0.0), (4.0, 0.0), (2.0, 0.0), (2.0, 2.0)]);
    assert!(matches!(折り返す, Err(単純多角形の生成の失敗::辺どうしが触れている { .. })), "{折り返す:?}");
}

#[test]
fn 点の位置は内側と境界の上と外側を分け凹んだ多角形でも正しい() {
    let 凹み = 多角形(&[(0.0, 0.0), (4.0, 0.0), (4.0, 4.0), (2.0, 1.0), (0.0, 4.0)]).expect("凹んだ五角形は単純多角形である");
    assert_eq!(凹み.点の位置(&点(1.0, 0.5)), 多角形に対する位置::内側);
    assert_eq!(凹み.点の位置(&点(2.0, 3.0)), 多角形に対する位置::外側, "凹みの中は外側である");
    assert_eq!(凹み.点の位置(&点(2.0, 0.0)), 多角形に対する位置::境界の上);
    assert_eq!(凹み.点の位置(&点(2.0, 1.0)), 多角形に対する位置::境界の上, "凹んだ頂点の上は境界の上である");
}

#[test]
fn 凹んだ頂点をかすめる線分は外へ出ず凹みを横切る線分は外へ出る() {
    let 凹み = 多角形(&[(0.0, 0.0), (4.0, 0.0), (4.0, 4.0), (2.0, 1.0), (0.0, 4.0)]).expect("凹んだ五角形は単純多角形である");
    let かすめる = 平面の線分 { 始点: 点(1.0, 0.5), 終点: 点(3.0, 1.5) };
    assert_eq!(凹み.線分が初めて外へ出る媒介変数(&かすめる), None);
    let 横切る = 平面の線分 { 始点: 点(0.5, 3.0), 終点: 点(3.5, 3.0) };
    let 出る位置 = 凹み.線分が初めて外へ出る媒介変数(&横切る).expect("凹みを横切る線分は外へ出る");
    assert!(出る位置 > 0.0 && 出る位置 < 0.5, "{出る位置}");
}

#[test]
fn 辺を共有して隣り合う多角形は重ならず食い込む多角形と同じ多角形と含む多角形は重なる() {
    let 基準 = 正方形(0.0, 0.0, 4.0);
    assert!(!基準.内部が重なるか(&正方形(4.0, 0.0, 4.0)), "辺を共有する隣の正方形は重ならない");
    assert!(!基準.内部が重なるか(&正方形(4.0, 4.0, 4.0)), "角だけを共有する正方形は重ならない");
    assert!(基準.内部が重なるか(&正方形(3.0, 1.0, 4.0)), "食い込む正方形は重なる");
    assert!(基準.内部が重なるか(&正方形(0.0, 0.0, 4.0)), "同じ正方形は重なる");
    assert!(基準.内部が重なるか(&正方形(1.0, 1.0, 2.0)), "内側に含まれる正方形は重なる");
    assert!(正方形(1.0, 1.0, 2.0).内部が重なるか(&基準), "含む側から見ても重なる");
    let 同じ辺の上の小さい長方形 = 多角形(&[(1.0, 0.0), (3.0, 0.0), (3.0, 1.0), (1.0, 1.0)]).expect("長方形は単純多角形である");
    assert!(基準.内部が重なるか(&同じ辺の上の小さい長方形), "辺の一部を同じ向きに共有する内側の長方形は重なる");
}

#[test]
fn 境界に沿わせた終点は辺に沿う成分だけを残し角では止まる() {
    let 基準 = 正方形(0.0, 0.0, 4.0);
    let 沿わせた = 基準.境界に沿わせた終点(&点(4.0, 1.0), &点(5.0, 2.0)).expect("辺の途中の点は辺に沿わせられる");
    assert_eq!(沿わせた, 点(4.0, 2.0));
    assert_eq!(基準.境界に沿わせた終点(&点(4.0, 4.0), &点(5.0, 5.0)), None, "角では沿わせる辺が決まらない");
    assert_eq!(基準.境界に沿わせた終点(&点(4.0, 1.0), &点(5.0, 1.0)), None, "辺に垂直な動きには沿う成分が無い");
}
