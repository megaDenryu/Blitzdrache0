//! 経路の開閉と旅行者の歩行の遷移の順序(開閉を遷移する → 通れる通り口を導く → 歩行を遷移する)が結果を決めることを固定する試験(Issue #187 の作業G2)。
//!
//! 峠道は10秒から20秒まで閉じる予定を持つ。村の(8, 5)から東へ3メートル歩く旅行者は、峠道が開いている刻みなら峠へ入る。
//! 峠道が閉じる時刻が来た刻み(10秒から11秒)では、開閉が先に遷移して峠道が閉じ、その後の歩行は閉じた峠道で遮られる。
//! あわせて、2つの遷移の失敗を独立に扱い、片方の失敗をこの遷移の出来事として返すこと(地図に無い経路の命令を拒んでも歩行は進み、歩行が失敗しても開閉は進む)を固定する。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::expect_used)]

use blitz_design::遷移成功結果;

use super::一つの区域の試料::現在地;
use super::地点と経路の試料::{刻み, 地図の外の経路, 封鎖できる経路を指す, 峠道が閉じる秒, 試験の地図を組む, 試験の規則を組む};
use crate::walking_direction::歩行方向;
use crate::地点と経路::地点と経路の図式::地点Id;
use crate::地点と経路::{経路の開閉, 経路の開閉の出来事, 経路の開閉の命令};
use crate::居場所::旅行者の居場所;
use crate::旅行者::{旅行者の出来事, 旅行者の意図, 歩行の規則};
use crate::経路の開閉と旅行者の歩行::{
    経路の開閉と旅行者の歩行の出来事, 経路の開閉と旅行者の歩行の更新への入力, 経路の開閉と旅行者の歩行の状態, 経路の開閉と旅行者の歩行の規則
};

type 更新の成功 = 遷移成功結果<経路の開閉と旅行者の歩行の状態, 経路の開閉と旅行者の歩行の出来事>;

fn 村の居場所(東: f32, 北: f32) -> 旅行者の居場所 {
    旅行者の居場所::生成する(試験の地図を組む().地点を確かめる(&地点Id("村".to_string())).expect("村は試験の地図に在る"), 現在地(東, 北))
}

// 規則のはじめの開閉の状態と、与えた居場所から、東へ歩く意図で1刻み進める。この地図の開閉の状態から始めるため、遷移そのものは失敗しない。
fn 東へ1回更新する(居場所: 旅行者の居場所, 命令: 経路の開閉の命令, 始まりの秒: f64) -> 更新の成功 {
    let 規則 = 経路の開閉と旅行者の歩行の規則::生成する(試験の規則を組む(), 歩行の規則::標準());
    let 状態 = 経路の開閉と旅行者の歩行の状態::生成する(規則.開閉の規則().はじめの状態(), 居場所);
    let 入力 = 経路の開閉と旅行者の歩行の更新への入力::生成する(命令, 旅行者の意図::歩く { 方向: 歩行方向::東() });
    状態.経路の開閉と旅行者の歩行を1回更新する(&入力, &規則, 刻み(始まりの秒, 1.0)).expect("この地図のはじめの開閉の状態からの遷移は失敗しないべきである")
}

#[test]
fn 峠道が開いている刻みでは峠道を通って峠へ入る() {
    let 結果 = 東へ1回更新する(村の居場所(8.0, 5.0), 経路の開閉の命令::命令が無い, 峠道が閉じる秒 - 2.0);
    assert_eq!(結果.次の状態.居場所().地点().表記(), "峠");
    assert!(結果.出来事一覧.is_empty(), "{:?}", 結果.出来事一覧);
}

#[test]
fn 峠道が閉じる刻みでは開閉が先に遷移し歩行は閉じた峠道で遮られる() {
    let 結果 = 東へ1回更新する(村の居場所(8.0, 5.0), 経路の開閉の命令::命令が無い, 峠道が閉じる秒);
    let 峠道 = 封鎖できる経路を指す(&試験の地図を組む(), "峠道");
    assert_eq!(
        結果.出来事一覧,
        vec![
            経路の開閉と旅行者の歩行の出来事::開閉の出来事(経路の開閉の出来事::経路が閉じた { 経路: 峠道.clone() }),
            経路の開閉と旅行者の歩行の出来事::旅行者の出来事(旅行者の出来事::障害物に遮られた)
        ]
    );
    assert_eq!(結果.次の状態.開閉の状態().経路の開閉(&峠道), 経路の開閉::閉じている);
    assert_eq!(結果.次の状態.居場所(), &村の居場所(10.0, 5.0), "閉じた峠道の手前の境目で止まるべきである");
    let 規則 = 経路の開閉と旅行者の歩行の規則::生成する(試験の規則を組む(), 歩行の規則::標準());
    let 入力 = 経路の開閉と旅行者の歩行の更新への入力::生成する(経路の開閉の命令::命令が無い, 旅行者の意図::歩く { 方向: 歩行方向::東() });
    let 次の刻み = 結果
        .次の状態
        .経路の開閉と旅行者の歩行を1回更新する(&入力, &規則, 刻み(峠道が閉じる秒 + 1.0, 1.0))
        .expect("閉じた峠道の手前からの遷移は失敗しないべきである");
    assert_eq!(次の刻み.次の状態.居場所(), &村の居場所(10.0, 5.0), "閉じた峠道は次の刻みでも通れない");
}

#[test]
fn 命令が峠道を閉じた刻みの歩行も閉じた峠道で遮られる() {
    let 峠道 = 封鎖できる経路を指す(&試験の地図を組む(), "峠道");
    let 結果 = 東へ1回更新する(村の居場所(8.0, 5.0), 経路の開閉の命令::経路を閉じる { 経路: 峠道 }, 0.0);
    assert_eq!(結果.次の状態.居場所(), &村の居場所(10.0, 5.0));
}

#[test]
fn 地図に無い経路の命令を拒んでも歩行は進み開閉を遷移できなかった出来事を返す() {
    let 結果 = 東へ1回更新する(村の居場所(8.0, 5.0), 経路の開閉の命令::経路を閉じる { 経路: 地図の外の経路() }, 0.0);
    assert!(matches!(結果.出来事一覧.as_slice(), [経路の開閉と旅行者の歩行の出来事::開閉を遷移できなかった(_)]), "{:?}", 結果.出来事一覧);
    assert_eq!(結果.次の状態.開閉の状態(), &試験の規則を組む().はじめの状態());
    assert_eq!(結果.次の状態.居場所().地点().表記(), "峠", "開閉の失敗に関わらず歩行は開いた峠道を通るべきである");
}

#[test]
fn 歩行が失敗しても開閉は進み歩行を遷移できなかった出来事を返す() {
    let 区域の外の居場所 = 村の居場所(50.0, 50.0);
    let 結果 = 東へ1回更新する(区域の外の居場所.clone(), 経路の開閉の命令::命令が無い, 峠道が閉じる秒);
    let 峠道 = 封鎖できる経路を指す(&試験の地図を組む(), "峠道");
    assert!(
        matches!(
            結果.出来事一覧.as_slice(),
            [経路の開閉と旅行者の歩行の出来事::開閉の出来事(経路の開閉の出来事::経路が閉じた { .. }), 経路の開閉と旅行者の歩行の出来事::歩行を遷移できなかった(_)]
        ),
        "{:?}",
        結果.出来事一覧
    );
    assert_eq!(結果.次の状態.開閉の状態().経路の開閉(&峠道), 経路の開閉::閉じている, "歩行の失敗に関わらず峠道は予定どおりに閉じるべきである");
    assert_eq!(結果.次の状態.居場所(), &区域の外の居場所, "失敗した歩行は居場所を変えないべきである");
}

#[test]
fn 両方の遷移が失敗した刻みは受け取った状態のまま2つのできなかった出来事を返す() {
    let 区域の外の居場所 = 村の居場所(50.0, 50.0);
    let 結果 = 東へ1回更新する(区域の外の居場所.clone(), 経路の開閉の命令::経路を閉じる { 経路: 地図の外の経路() }, 0.0);
    assert!(
        matches!(結果.出来事一覧.as_slice(), [経路の開閉と旅行者の歩行の出来事::開閉を遷移できなかった(_), 経路の開閉と旅行者の歩行の出来事::歩行を遷移できなかった(_)]),
        "{:?}",
        結果.出来事一覧
    );
    assert_eq!(結果.次の状態.開閉の状態(), &試験の規則を組む().はじめの状態());
    assert_eq!(結果.次の状態.居場所(), &区域の外の居場所);
}
