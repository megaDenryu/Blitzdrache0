//! 経路の開閉と旅行者の歩行の状態遷移の順序(開閉を状態遷移させる → 歩行の規則を組む → 歩行を状態遷移させる)が結果を決めることを固定する試験(Issue #187 の作業G2)。
//!
//! 峠道は10秒から20秒まで閉じる予定を持つ。村の(8, 5)から東へ3メートル歩く旅行者は、峠道が開いている刻みなら峠へ入る。
//! 峠道が閉じる時刻が来た刻み(10秒から11秒)では、開閉が先に状態遷移して峠道が閉じ、その後の歩行は閉じた峠道で遮られる。
//! あわせて、1刻みが失敗しないことと、地図に無い経路の命令と区域の外にいる居場所をプログラムの誤りとして停止させること(2026-09-28 オーナー裁定。設計オントロジー 3.5.9)を固定する。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::expect_used)]

use blitz_design::状態遷移成功結果;

use super::一つの区域の試料::現在地;
use super::地点と経路の試料::{刻み, 地図の外の経路, 封鎖できる経路を指す, 峠道が閉じる秒, 試験の地図を組む, 試験の規則を組む};
use crate::walking_direction::歩行方向;
use crate::地点と経路::地点と経路の図式::地点Id;
use crate::地点と経路::{経路の開閉, 経路の開閉の出来事, 経路の開閉の命令};
use crate::居場所::旅行者の居場所;
use crate::旅行者::{旅行者の出来事, 旅行者の意図, 歩行の規則};
use crate::経路の開閉と旅行者の歩行::{
    経路の開閉と旅行者の歩行の出来事, 経路の開閉と旅行者の歩行の更新への入力, 経路の開閉と旅行者の歩行の状態, 経路の開閉と旅行者の歩行の規則
};

type 更新の成功 = 状態遷移成功結果<経路の開閉と旅行者の歩行の状態, 経路の開閉と旅行者の歩行の出来事>;

fn 村の居場所(東: f32, 北: f32) -> 旅行者の居場所 {
    旅行者の居場所::生成する(試験の地図を組む().地点を確かめる(&地点Id("村".to_string())).expect("村は試験の地図に在る"), 現在地(東, 北))
}

// 規則のはじめの開閉の状態と、与えた居場所から、東へ歩く意図で1刻み進める。1刻みは失敗しない状態遷移であり、失敗の選択肢は値を持たない。
fn 東へ1回更新する(居場所: 旅行者の居場所, 命令: 経路の開閉の命令, 始まりの秒: f64) -> 更新の成功 {
    let 規則 = 経路の開閉と旅行者の歩行の規則::生成する(試験の規則を組む(), 歩行の規則::標準());
    let 状態 = 経路の開閉と旅行者の歩行の状態::生成する(規則.開閉の規則().はじめの状態(), 居場所);
    let 入力 = 経路の開閉と旅行者の歩行の更新への入力::生成する(命令, 旅行者の意図::歩く { 方向: 歩行方向::東() });
    match 状態.経路の開閉と旅行者の歩行を1回更新する(&入力, &規則, 刻み(始まりの秒, 1.0)) {
        Ok(成功) => 成功,
        Err(失敗) => 失敗.起こらない失敗の分岐を閉じる(),
    }
}

#[test]
fn 峠道が開いている刻みでは峠道を通って峠へ入る() {
    let 結果 = 東へ1回更新する(村の居場所(8.0, 5.0), 経路の開閉の命令::命令が無い, 峠道が閉じる秒 - 2.0);
    assert_eq!(結果.次の状態().居場所().地点().表記(), "峠");
    assert!(結果.出来事一覧().is_empty(), "{:?}", 結果.出来事一覧());
}

#[test]
fn 峠道が閉じる刻みでは開閉が先に状態遷移し歩行は閉じた峠道で遮られる() {
    let 結果 = 東へ1回更新する(村の居場所(8.0, 5.0), 経路の開閉の命令::命令が無い, 峠道が閉じる秒);
    let 峠道 = 封鎖できる経路を指す(&試験の地図を組む(), "峠道");
    assert_eq!(
        結果.出来事一覧(),
        vec![
            経路の開閉と旅行者の歩行の出来事::開閉の出来事(経路の開閉の出来事::経路が閉じた { 経路: 峠道.clone() }),
            経路の開閉と旅行者の歩行の出来事::旅行者の出来事(旅行者の出来事::障害物に遮られた)
        ]
    );
    assert_eq!(結果.次の状態().開閉の状態().経路の開閉(&峠道), 経路の開閉::閉じている);
    assert_eq!(結果.次の状態().居場所(), &村の居場所(10.0, 5.0), "閉じた峠道の手前の境目で止まるべきである");
    let 規則 = 経路の開閉と旅行者の歩行の規則::生成する(試験の規則を組む(), 歩行の規則::標準());
    let 入力 = 経路の開閉と旅行者の歩行の更新への入力::生成する(経路の開閉の命令::命令が無い, 旅行者の意図::歩く { 方向: 歩行方向::東() });
    let 次の刻み = match 結果.次の状態を取り出す().経路の開閉と旅行者の歩行を1回更新する(&入力, &規則, 刻み(峠道が閉じる秒 + 1.0, 1.0)) {
        Ok(成功) => 成功,
        Err(失敗) => 失敗.起こらない失敗の分岐を閉じる(),
    };
    assert_eq!(次の刻み.次の状態().居場所(), &村の居場所(10.0, 5.0), "閉じた峠道は次の刻みでも通れない");
}

#[test]
fn 命令が峠道を閉じた刻みの歩行も閉じた峠道で遮られる() {
    let 峠道 = 封鎖できる経路を指す(&試験の地図を組む(), "峠道");
    let 結果 = 東へ1回更新する(村の居場所(8.0, 5.0), 経路の開閉の命令::経路を閉じる { 経路: 峠道 }, 0.0);
    assert_eq!(結果.次の状態().居場所(), &村の居場所(10.0, 5.0));
}

#[test]
#[should_panic(expected = "規則の地図に無い経路を受け取った")]
fn 地図に無い経路の命令はプログラムの誤りとして1刻みを停止させる() {
    let _ = 東へ1回更新する(村の居場所(8.0, 5.0), 経路の開閉の命令::経路を閉じる { 経路: 地図の外の経路() }, 0.0);
}

#[test]
#[should_panic(expected = "旅行者の居場所が空間制約の区域の中に無い")]
fn 区域の外にいる居場所はプログラムの誤りとして1刻みを停止させる() {
    let _ = 東へ1回更新する(村の居場所(50.0, 50.0), 経路の開閉の命令::命令が無い, 峠道が閉じる秒);
}
