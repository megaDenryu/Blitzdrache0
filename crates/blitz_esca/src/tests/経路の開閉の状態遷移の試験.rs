//! 経路の開閉の状態遷移の反例を固定する試験(Issue #187 の作業G1)。
//!
//! 固定する反例は3つである。(i) 地図に無い経路を開く・閉じる命令は、プログラムの誤りとして状態遷移を停止させる(2026-09-28 オーナー裁定。状態の作り方の反例は `経路の開閉の状態の作り方の試験.rs` が持つ)。
//! (ii) すでに閉じている経路を閉じる命令は、閉じている経路を変えず出来事も生まない(法則E2)。その経路は出来事が触れた経路になり、以後の時刻の予定を受けない。
//! (iii) 同じ刻みで時刻が閉じた経路を命令が開けば、命令が指す経路には予定を当てないため(出来事が勝つ。2026-09-26 オーナー裁定)経路は開いたまま残り、前後の開閉が同じなので出来事を生まない。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::expect_used)]

use super::地点と経路の試料::{刻み, 地図の外の経路, 封鎖できる経路を指す, 峠道が閉じる秒, 峠道が開く秒, 試験の地図を組む, 試験の規則を組む};
use crate::transition_parameter::状態遷移パラメータ;
use crate::地点と経路::{経路の開閉, 経路の開閉の出来事, 経路の開閉の命令, 経路の開閉の状態};
use blitz_design::{状態遷移失敗結果, 状態遷移成功結果};
use std::convert::Infallible;

type 開閉の状態遷移の結果 = Result<状態遷移成功結果<経路の開閉の状態, 経路の開閉の出来事>, 状態遷移失敗結果<経路の開閉の状態, Infallible>>;

fn 状態遷移させる(状態: 経路の開閉の状態, 命令: 経路の開閉の命令, パラメータ: 状態遷移パラメータ) -> 開閉の状態遷移の結果 {
    状態.開閉を状態遷移させる(&命令, &試験の規則を組む(), パラメータ)
}

fn はじめの状態() -> 経路の開閉の状態 {
    試験の規則を組む().はじめの状態()
}

// 峠道の予定も時刻の予定も来ない、0秒から1秒までの刻み。
fn 予定の来ない刻み() -> 状態遷移パラメータ {
    刻み(0.0, 1.0)
}

#[test]
#[should_panic(expected = "規則の地図に無い経路を受け取った")]
fn 反例i_地図に無い経路を閉じる命令はプログラムの誤りとして停止する() {
    let _ = 状態遷移させる(はじめの状態(), 経路の開閉の命令::経路を閉じる { 経路: 地図の外の経路() }, 予定の来ない刻み());
}

#[test]
#[should_panic(expected = "規則の地図に無い経路を受け取った")]
fn 反例i_地図に無い経路を開く命令はプログラムの誤りとして停止する() {
    let _ = 状態遷移させる(はじめの状態(), 経路の開閉の命令::経路を開く { 経路: 地図の外の経路() }, 刻み(峠道が閉じる秒, 1.0));
}

#[test]
fn 反例ii_すでに閉じている経路を閉じる命令は閉じている経路を変えず出来事を生まない() {
    let 関所 = 封鎖できる経路を指す(&試験の地図を組む(), "関所");
    let 成功 = 状態遷移させる(はじめの状態(), 経路の開閉の命令::経路を閉じる { 経路: 関所.clone() }, 予定の来ない刻み()).expect("地図に在る経路の命令は成功するべきである");
    assert!(成功.次の状態.閉じている経路一覧().eq(はじめの状態().閉じている経路一覧()), "閉じている経路が変わった");
    assert!(成功.次の状態.出来事が触れた経路一覧().eq([&関所]), "命令が指した関所が出来事が触れた経路に入っていない");
    assert!(成功.出来事一覧.is_empty(), "開閉が変わらないのに出来事が生じた: {:?}", 成功.出来事一覧);
}

#[test]
fn 開いている経路を閉じる命令は経路が閉じたを1件生む() {
    let 橋 = 封鎖できる経路を指す(&試験の地図を組む(), "橋");
    let 成功 = 状態遷移させる(はじめの状態(), 経路の開閉の命令::経路を閉じる { 経路: 橋.clone() }, 予定の来ない刻み()).expect("地図に在る経路の命令は成功するべきである");
    assert_eq!(成功.次の状態.経路の開閉(&橋), 経路の開閉::閉じている);
    assert_eq!(成功.出来事一覧, vec![経路の開閉の出来事::経路が閉じた { 経路: 橋 }]);
}

#[test]
fn 時間帯の始まりが来た刻みで経路が閉じ終わりが来た刻みで開く() {
    let 峠道 = 封鎖できる経路を指す(&試験の地図を組む(), "峠道");
    let 閉じた後の結果 = 状態遷移させる(はじめの状態(), 経路の開閉の命令::命令が無い, 刻み(峠道が閉じる秒 - 0.5, 1.0)).expect("命令が無い状態遷移は成功するべきである");
    assert_eq!(閉じた後の結果.出来事一覧, vec![経路の開閉の出来事::経路が閉じた { 経路: 峠道.clone() }]);
    let 開いた後の結果 = 状態遷移させる(閉じた後の結果.次の状態, 経路の開閉の命令::命令が無い, 刻み(峠道が開く秒, 1.0)).expect("命令が無い状態遷移は成功するべきである");
    assert_eq!(開いた後の結果.出来事一覧, vec![経路の開閉の出来事::経路が開いた { 経路: 峠道 }]);
    assert_eq!(開いた後の結果.次の状態, はじめの状態());
}

#[test]
fn 反例iii_同じ刻みで時刻が閉じた経路を命令が開けば開いたまま残り出来事を生まない() {
    let 峠道 = 封鎖できる経路を指す(&試験の地図を組む(), "峠道");
    let 成功 = 状態遷移させる(はじめの状態(), 経路の開閉の命令::経路を開く { 経路: 峠道.clone() }, 刻み(峠道が閉じる秒, 1.0)).expect("地図に在る経路の命令は成功するべきである");
    assert_eq!(成功.次の状態.経路の開閉(&峠道), 経路の開閉::開いている, "命令が指す経路に時刻の予定を当てている");
    assert!(成功.出来事一覧.is_empty(), "前後の開閉が同じなのに出来事が生じた: {:?}", 成功.出来事一覧);
}

#[test]
fn 同じ刻みで時刻と命令がどちらも閉じた経路の出来事は1件だけである() {
    let 峠道 = 封鎖できる経路を指す(&試験の地図を組む(), "峠道");
    let 成功 = 状態遷移させる(はじめの状態(), 経路の開閉の命令::経路を閉じる { 経路: 峠道.clone() }, 刻み(峠道が閉じる秒, 1.0)).expect("地図に在る経路の命令は成功するべきである");
    assert_eq!(成功.出来事一覧, vec![経路の開閉の出来事::経路が閉じた { 経路: 峠道 }]);
}

#[test]
fn 経過時間が0の刻みは始まりの時刻に来る予定も当てない() {
    let 成功 = 状態遷移させる(はじめの状態(), 経路の開閉の命令::命令が無い, 刻み(峠道が閉じる秒, 0.0)).expect("命令が無い状態遷移は成功するべきである");
    assert_eq!(成功.次の状態, はじめの状態());
    assert!(成功.出来事一覧.is_empty());
}
