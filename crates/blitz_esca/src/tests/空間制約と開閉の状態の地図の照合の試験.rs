//! 通れる通り口を導く口が、開閉の状態の経路がその地図に在ることを確かめ、別の地図の状態を型付きの失敗で拒むことを固定する試験(Issue #187 の作業G2)。
//!
//! 別の地図の状態から通れる通り口を導くと、その状態はこの地図の閉じている門を閉じている経路に持たないため、閉じている門を開いていると判断する。
//! 開閉の遷移が状態の経路を規則の地図で確かめる規律(`経路の開閉の状態の作り方の試験.rs`)と同じ規律を、空間制約と歩行の規則と旅の進行の始まりにも固定する。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::expect_used)]

use super::一つの区域の試料::現在地;
use super::地点と経路の試料::{地図の外の経路, 試験の地図を組む, 試験の規則を組む, 隠し道だけの地図を組む};
use crate::traveler::歩行の規則;
use crate::traveler_movement::歩行遷移の規則;
use crate::地点と経路::地点と経路の図式::地点Id;
use crate::地点と経路::{区域の空間制約, 経路の指定の失敗, 経路の開閉の状態, 経路の開閉の状態の指定, 経路の開閉の規則};
use crate::居場所::旅行者の居場所;
use crate::旅の一刻み::{旅の進行, 旅の進行の指定};

// 隠し道だけの地図の規則が確かめた、隠し道を閉じている経路か出来事が触れた経路に持つ状態。試験の地図には隠し道が無い。
fn 別の地図の状態(閉じているか: bool) -> 経路の開閉の状態 {
    let 隠し道 = vec![地図の外の経路()];
    let 指定 = if 閉じているか {
        経路の開閉の状態の指定 {
            閉じている経路: 隠し道,
            出来事が触れた経路: Vec::new(),
        }
    } else {
        経路の開閉の状態の指定 {
            閉じている経路: Vec::new(),
            出来事が触れた経路: 隠し道,
        }
    };
    経路の開閉の規則::生成する(隠し道だけの地図を組む())
        .指定を地図で確かめて状態を作る(指定)
        .expect("隠し道だけの地図の経路の指定は、その地図の規則で状態になるべきである")
}

fn 地図に無い隠し道() -> 経路の指定の失敗 {
    経路の指定の失敗::地図に無い経路を指した { 経路: 地図の外の経路() }
}

#[test]
fn 別の地図の状態から空間制約を導くと閉じている経路も出来事が触れた経路も地図に無いとして拒まれる() {
    for 閉じているか in [true, false] {
        let 導いた = 区域の空間制約::開閉の状態から導く(試験の地図を組む(), &別の地図の状態(閉じているか));
        assert_eq!(導いた.err(), Some(地図に無い隠し道()), "隠し道を閉じているか: {閉じているか}");
    }
}

#[test]
fn 同じ地図の状態からは空間制約を導けて閉じている関所は通れる通り口に入らない() {
    let 空間制約 = 区域の空間制約::開閉の状態から導く(試験の地図を組む(), &試験の規則を組む().はじめの状態()).expect("同じ地図の状態からは導けるべきである");
    let 通り口の数 = 空間制約.通れる通り口().通り口一覧().len();
    assert_eq!(通り口の数, 試験の地図を組む().通り口一覧().len() - 1, "5本の経路の通り口のうち、はじめに閉じている関所の1つだけが通れない");
}

#[test]
fn 別の地図の状態で歩行の規則の通れる通り口を導き直すと拒まれる() {
    let 空間制約 = 区域の空間制約::開閉の状態から導く(試験の地図を組む(), &試験の規則を組む().はじめの状態()).expect("同じ地図の状態からは導けるべきである");
    let 規則 = 歩行遷移の規則::生成する(歩行の規則::標準(), 空間制約);
    assert_eq!(規則.通れる通り口を導き直す(&別の地図の状態(true)).err(), Some(地図に無い隠し道()));
}

#[test]
fn 別の地図の状態を渡すと旅の進行を始められない() {
    let 村 = 試験の地図を組む().地点を確かめる(&地点Id("村".to_string())).expect("村は試験の地図に在る");
    let 始めた = 旅の進行::始める(旅の進行の指定 {
        開閉の規則: 試験の規則を組む(),
        開閉の状態: 別の地図の状態(true),
        居場所: 旅行者の居場所::生成する(村, 現在地(5.0, 5.0)),
        身体: 歩行の規則::標準(),
    });
    assert_eq!(始めた.err(), Some(地図に無い隠し道()));
}
