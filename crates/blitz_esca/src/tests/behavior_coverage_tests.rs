//! 網羅していない領域での、証拠の出方の非対称を固定する試験(Issue #174)。
//!
//! 全称命題の反例と、存在命題の実例は見た範囲から得られるが、全称の成立と存在の不在は見ていない範囲に依る。
//! したがって同じ標本の上でも、命題の形によって答えてよい結果が違う。その違いをここで固定する。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::unwrap_used)]

use blitz_design_verification::{命題の検証器, 数え上げの網羅性, 未決定の理由, 検証結果};

use super::behavior_domain::旅行者の歩行を数え上げる領域;
use super::behavior_landmark::{移動可能範囲の内側から東へ一回歩いた現在地, 移動可能範囲の内側の現在地, 移動可能範囲の外の現在地, 移動可能範囲の東の端の現在地};
use super::behavior_proposition::{
    その現在地が到達可能である命題を組む, その遷移でその出来事が発生する命題を組む, その遷移で障害物に遮られたが発生する命題を組む, 内側を東へ歩いても障害物に遮られるという偽の命題を組む, 到達可能な状態が1つ在る命題を組む,
    端から範囲の外へ歩くと障害物に遮られる命題を組む,
};
use crate::traveler::旅行者の出来事;

#[test]
fn 歩行の数え上げの網羅性は連続量の標本に限ると答える() {
    let 領域 = 旅行者の歩行を数え上げる領域::生成する();
    match 領域.遷移モデルと網羅性を組む().網羅性 {
        数え上げの網羅性::連続量の標本に限る { 説明一覧 } => assert!(!説明一覧.is_empty(), "連続量の説明が1件も無い"),
        それ以外 => panic!("歩行方向が連続量であるのに網羅性が標本に限るで返らなかった: {それ以外:?}"),
    }
}

#[test]
fn 端から範囲の外へ歩く代表ケースの命題は標本の全件で成立しても未決定になる() {
    // 標本の全件で成立したが、歩行方向 が単精度2成分の連続量であるため証明済みと偽らない(Issue #174 のオーナー裁定)。
    let 領域 = 旅行者の歩行を数え上げる領域::生成する();
    let 命題 = 端から範囲の外へ歩くと障害物に遮られる命題を組む(&移動可能範囲の東の端の現在地());
    match 領域.検証器を組む().検証する(&命題) {
        検証結果::未決定(未決定の理由::探索の範囲では反例が無い { 探索した件数, 探索の範囲の説明 }) => {
            assert!(探索した件数 > 0, "探索した件数が0件である");
            assert!(探索の範囲の説明.contains("歩行方向"), "見ていない範囲が残る理由に歩行方向の連続量が書かれていない: {探索の範囲の説明}");
        }
        それ以外 => panic!("代表ケースの命題が探索の範囲では反例が無いの未決定にならなかった: {}", それ以外.表記()),
    }
}

#[test]
fn 内側を東へ歩く遷移についての偽の全称の命題は網羅していなくても反証済みになる() {
    let 領域 = 旅行者の歩行を数え上げる領域::生成する();
    let 偽の命題 = 内側を東へ歩いても障害物に遮られるという偽の命題を組む(&移動可能範囲の内側の現在地(), &移動可能範囲の内側から東へ一回歩いた現在地());
    let 結果 = 領域.検証器を組む().検証する(&偽の命題);
    assert!(結果.反証済みか(), "標本の中に反例が在るのに反証済みにならなかった: {}", 結果.表記());
}

#[test]
fn 名指した1件の遷移についての偽の命題の反例に前状態と入力と得られた出来事が入る() {
    let 領域 = 旅行者の歩行を数え上げる領域::生成する();
    let 遷移の概念 = 領域.東へ歩く遷移を名指す(&移動可能範囲の内側の現在地()).unwrap();
    let 偽の命題 = その遷移で障害物に遮られたが発生する命題を組む(遷移の概念);
    match 領域.検証器を組む().検証する(&偽の命題) {
        検証結果::反証済み(反例) => {
            let 材料の名前一覧: Vec<&str> = 反例.再現の材料.iter().map(|(名前, _)| 名前.as_str()).collect();
            for 要る名前 in ["前状態", "入力", "得られた出来事"] {
                assert!(材料の名前一覧.contains(&要る名前), "反例の再現の材料に{要る名前}が無い");
            }
        }
        それ以外 => panic!("境界に当たらない遷移で障害物に遮られたを問うて反証済みにならなかった: {}", それ以外.表記()),
    }
}

#[test]
fn 到達可能な状態が1つ在るという存在命題は実例が在るため証明済みになる() {
    let 領域 = 旅行者の歩行を数え上げる領域::生成する();
    let 命題 = 到達可能な状態が1つ在る命題を組む();
    let 結果 = 領域.検証器を組む().検証する(&命題);
    assert!(結果.証明済みか(), "標本の中で見つかった実例が本物の実例として扱われなかった: {}", 結果.表記());
}

#[test]
fn 移動可能範囲の外の現在地が到達可能であるは到達可能な状態の中に見つからないため反証済みでなく未決定になる() {
    let 領域 = 旅行者の歩行を数え上げる領域::生成する();
    let 命題 = その現在地が到達可能である命題を組む(&移動可能範囲の外の現在地());
    let 結果 = 領域.検証器を組む().検証する(&命題);
    assert!(!結果.証明済みか() && !結果.反証済みか(), "到達可能な状態の中に見つからない到達可能であるが未決定にならなかった: {}", 結果.表記());
}

#[test]
fn 別の出来事についての発生するは同じ遷移でも交差しない() {
    // 2つの出来事は別の名指しへ写るため、障害物に遮られたを生成した遷移で周囲を観察したを問えば反証済みになる。
    // 名指しが2つを同じ参照へまとめれば、この問いは証明済みへ転び、障害物に遮られたしか起きていない遷移で周囲を観察したの発生が通る。
    let 領域 = 旅行者の歩行を数え上げる領域::生成する();
    let 遷移の概念 = 領域.東へ歩く遷移を名指す(&移動可能範囲の東の端の現在地()).unwrap();
    let 検証器 = 領域.検証器を組む();
    let 障害物の命題 = その遷移でその出来事が発生する命題を組む(遷移の概念.clone(), 旅行者の出来事::障害物に遮られた);
    let 観察の命題 = その遷移でその出来事が発生する命題を組む(遷移の概念, 旅行者の出来事::周囲を観察した);
    assert!(検証器.検証する(&障害物の命題).証明済みか(), "境界に当たる遷移で障害物に遮られたが証明済みにならなかった");
    assert!(検証器.検証する(&観察の命題).反証済みか(), "障害物に遮られただけを生成した遷移で、周囲を観察したの発生が反証済みにならなかった");
}
