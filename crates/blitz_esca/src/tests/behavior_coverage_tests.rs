//! 網羅していない領域での、証拠の出方の非対称を固定する試験(Issue #174)。
//!
//! 反例と存在の証人は見た範囲から得られるが、全称の成立と存在の不在は見ていない範囲に依る。
//! したがって同じ標本の上でも、命題の形によって答えてよい結末が違う。その違いをここで固定する。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::unwrap_used)]

use blitz_design_verification::{命題の検証器, 数え上げの網羅性, 未決定の理由, 検証結果};

use super::behavior_domain::旅行者の歩行を数え上げる領域;
use super::behavior_proposition::旅行者の歩行の命題を組む工程;

fn 命題を組む工程を用意する(領域: &旅行者の歩行を数え上げる領域) -> 旅行者の歩行の命題を組む工程 {
    旅行者の歩行の命題を組む工程::生成する(領域.マスの一辺())
}

#[test]
fn 歩行の数え上げの網羅性は連続量の標本に限ると答える() {
    let 領域 = 旅行者の歩行を数え上げる領域::生成する();
    match 領域.探索の結末を組む().網羅性 {
        数え上げの網羅性::連続量の標本に限る { 説明一覧 } => assert!(!説明一覧.is_empty(), "連続量の説明が1件も無い"),
        それ以外 => panic!("歩行方向が連続量であるのに網羅性が標本に限るで返らなかった: {それ以外:?}"),
    }
}

#[test]
fn 端から範囲の外へ歩く代表ケースの命題は標本の全件で成立しても未決定になる() {
    // 標本の全件で成立したが、歩行方向 が単精度2成分の連続量であるため証明済みと偽らない(Issue #174 のオーナー裁定)。
    let 領域 = 旅行者の歩行を数え上げる領域::生成する();
    let 命題 = 命題を組む工程を用意する(&領域).端から範囲の外へ歩くと障害物に遮られる命題を組む(&領域.東の端の現在地());
    match 領域.検証器を組む().検証する(&命題) {
        検証結果::未決定(未決定の理由::探索の範囲では反例が無い { 探索した件数, 探索の範囲の説明 }) => {
            assert!(探索した件数 > 0, "探索した件数が0件である");
            assert!(探索の範囲の説明.contains("歩行方向"), "見ていない範囲が残る理由に歩行方向の連続量が書かれていない: {探索の範囲の説明}");
        }
        それ以外 => panic!("代表ケースの命題が探索の範囲では反例が無いの未決定にならなかった: {}", それ以外.表記()),
    }
}

#[test]
fn 内側を東へ歩く遷移についての偽の全称の命題は網羅していなくても反証済みになる() {
    let 領域 = 旅行者の歩行を数え上げる領域::生成する();
    let 偽の命題 = 命題を組む工程を用意する(&領域).内側を東へ歩いても障害物に遮られるという偽の命題を組む(&領域.内側の現在地(), &領域.内側から東へ歩いた現在地());
    let 結末 = 領域.検証器を組む().検証する(&偽の命題);
    assert!(結末.反証済みか(), "標本の中に反例が在るのに反証済みにならなかった: {}", 結末.表記());
}

#[test]
fn 名指した1件の遷移についての偽の命題の反例に前状態と入力と得られた出来事が入る() {
    let 領域 = 旅行者の歩行を数え上げる領域::生成する();
    let 遷移の概念 = 領域.内側を東へ歩く遷移を名指す().unwrap();
    let 偽の命題 = 命題を組む工程を用意する(&領域).その遷移で障害物に遮られたが発生する命題を組む(遷移の概念);
    match 領域.検証器を組む().検証する(&偽の命題) {
        検証結果::反証済み(反例) => {
            let 材料の名前一覧: Vec<&str> = 反例.再現の材料.iter().map(|(名前, _)| 名前.as_str()).collect();
            for 要る名前 in ["前状態", "入力", "得られた出来事"] {
                assert!(材料の名前一覧.contains(&要る名前), "反例の再現の材料に{要る名前}が無い");
            }
        }
        それ以外 => panic!("境界に当たらない遷移で障害物に遮られたを問うて反証済みにならなかった: {}", それ以外.表記()),
    }
}

#[test]
fn 到達可能な状態が1つ在る存在の命題は証人が在るため証明済みになる() {
    let 領域 = 旅行者の歩行を数え上げる領域::生成する();
    let 命題 = 命題を組む工程を用意する(&領域).到達可能な状態が1つ在る命題を組む();
    let 結末 = 領域.検証器を組む().検証する(&命題);
    assert!(結末.証明済みか(), "標本の中の証人が本物の証人として扱われなかった: {}", 結末.表記());
}

#[test]
fn 移動可能範囲の外の現在地が到達可能であるは証人が無いため反証済みでなく未決定になる() {
    let 領域 = 旅行者の歩行を数え上げる領域::生成する();
    let 命題 = 命題を組む工程を用意する(&領域).その現在地が到達可能である命題を組む(&領域.範囲の外の現在地());
    let 結末 = 領域.検証器を組む().検証する(&命題);
    assert!(!結末.証明済みか() && !結末.反証済みか(), "証人の無い到達可能であるが未決定にならなかった: {}", 結末.表記());
}
