//! 斜めの壁と凹んだ頂点を持つ区域の上で、多くの始点・向き・速さの歩行を続けても、旅行者がいつも区域の閉包の中に留まり遷移が失敗しないことを確かめる試験(Issue #187 の作業G2)。
//!
//! 有限全数の検証(`旅の数え上げの試験.rs`)が確かめるのは、軸に揃った正方形の区域と5メートルの格子と軸方向の4つの向きだけであり、斜めの壁・境界の許容幅・滑り・凹んだ頂点を通らない。
//! この試験はその外側を、座標1000メートルの凹んだ区域の上の決まった標本で確かめる。全状態の主張ではなく、標本の上の主張である。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::expect_used)]

use blitz_math::メートル毎秒;

use super::一つの区域の試料::{一つの区域の広場, 現在地, 経過};
use crate::traveler::{旅行者の出来事, 旅行者の意図, 歩行の規則};
use crate::traveler_input::キーボード歩行入力;
use crate::walking_direction::歩行方向;
use crate::居場所::旅行者の居場所;

const 原点: f32 = 1000.0; // 区域を置く座標の大きさ。境界の許容幅が約1ミリメートルになる
const 速さ一覧: [f32; 4] = [0.37, 1.3, 3.7, 7.1];
const 同じ向きに続ける刻みの数: usize = 3;

#[test]
fn 凹んだ頂点と斜めの壁を持つ区域でどの標本の歩行を続けても旅行者は閉包の中に留まる() {
    let 広場 = 凹んだ広場();
    let 向き一覧 = 向き一覧();
    assert_eq!(向き一覧.len(), 8, "8つの向きを試すべきである");
    let mut 遮られた刻みの数 = 0;
    for 速さ in 速さ一覧 {
        let 規則 = 広場.歩行の規則を組む(歩行の規則::生成する(メートル毎秒::生成する(速さ)).expect("有限な0以上の速さは規則になるべきである"));
        for 始点 in 始点一覧(&広場) {
            for (番号, 向き) in 向き一覧.iter().enumerate() {
                let 曲がった向き = 向き一覧[(番号 + 3) % 向き一覧.len()];
                let mut 居場所 = 広場.広場の居場所(現在地(始点.0, 始点.1));
                for 刻みの向き in std::iter::repeat_n(*向き, 同じ向きに続ける刻みの数).chain(std::iter::repeat_n(曲がった向き, 同じ向きに続ける刻みの数)) {
                    let 題 = format!("速さ{速さ} 始点{始点:?} 向き{刻みの向き:?}");
                    let 成功 = 居場所
                        .歩行を遷移する(&旅行者の意図::歩く { 方向: 刻みの向き }, &規則, 経過(1.0))
                        .unwrap_or_else(|失敗| panic!("{題}: 遷移が失敗した: {:?}", 失敗.失敗の理由));
                    遮られた刻みの数 += 成功.出来事一覧.iter().filter(|出来事| **出来事 == 旅行者の出来事::障害物に遮られた).count();
                    居場所 = 成功.次の状態;
                    閉包の中にあることを確かめる(&広場, &居場所, &題);
                }
            }
        }
    }
    assert!(遮られた刻みの数 > 0, "標本の歩行が一度も壁に当たっていない(試験が空虚に通っている)");
}

fn 閉包の中にあることを確かめる(広場: &一つの区域の広場, 居場所: &旅行者の居場所, 題: &str) {
    let 点 = 居場所.現在地().平面の点へ広げる();
    assert!(広場.区域.多角形().閉包に入るか(&点), "{題}: 閉包の外に着いた: {点:?}");
}

// 一辺10メートルの正方形の東の辺を、(6, 6)の凹んだ頂点へ食い込ませた多角形。(10, 4)から(6, 6)と、(6, 6)から(10, 10)の2本が斜めの壁である。
fn 凹んだ広場() -> 一つの区域の広場 {
    let 頂点一覧 = [(0.0, 0.0), (10.0, 0.0), (10.0, 4.0), (6.0, 6.0), (10.0, 10.0), (0.0, 10.0)];
    一つの区域の広場::頂点から作る(&頂点一覧.map(|(東, 北)| (原点 + 東, 原点 + 北)))
}

// 8つの向き。上下と左右のキーを、相反するキーを押さない組み合わせで押したときの向きである。
fn 向き一覧() -> Vec<歩行方向> {
    let 押し方 = [(false, false), (true, false), (false, true)];
    押し方
        .iter()
        .flat_map(|(上, 下)| 押し方.iter().map(move |(左, 右)| キーボード歩行入力 { 上: *上, 下: *下, 左: *左, 右: *右 }))
        .filter_map(|入力| 歩行方向::キー入力から導く(&入力))
        .collect()
}

// 1メートルおきの格子の点のうち区域の閉包に入るものと、凹んだ頂点と、2本の斜めの壁の中ほどの点。
fn 始点一覧(広場: &一つの区域の広場) -> Vec<(f32, f32)> {
    let 格子 = (0u8..=10).flat_map(|東| (0u8..=10).map(move |北| (原点 + f32::from(東), 原点 + f32::from(北))));
    let 壁の上 = [(6.0, 6.0), (8.0, 5.0), (8.0, 8.0)].map(|(東, 北)| (原点 + 東, 原点 + 北));
    格子.chain(壁の上).filter(|(東, 北)| 広場.区域.多角形().閉包に入るか(&現在地(*東, *北).平面の点へ広げる())).collect()
}
