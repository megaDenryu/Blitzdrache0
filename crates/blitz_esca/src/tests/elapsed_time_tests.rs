//! 経過時間の検証付き生成のテスト(Issue #137)。有限かつ0以上の不変条件を固定する。

#![allow(clippy::expect_used)]

use blitz_math::秒;

use crate::elapsed_time::{経過時間, 経過時間の生成の失敗};

#[test]
fn 経過時間_有限な0以上の数値だけを受け入れる() {
    let 零 = 経過時間::生成する(秒::生成する(0.0)).expect("0秒は受け入れるべきである");
    assert_eq!(零.秒(), 秒::生成する(0.0));
    let 正 = 経過時間::生成する(秒::生成する(2.0)).expect("2秒は受け入れるべきである");
    assert_eq!(正.秒(), 秒::生成する(2.0));
}

#[test]
fn 経過時間_負とnanと無限大は拒まれる() {
    for 値 in [-1.0, f32::NAN, f32::INFINITY, f32::NEG_INFINITY] {
        let 失敗 = 経過時間::生成する(秒::生成する(値)).expect_err("負・NaN・無限大の経過時間は拒まれるべきである");
        assert!(matches!(失敗, 経過時間の生成の失敗::有限な0以上の数値でない { .. }));
    }
}
