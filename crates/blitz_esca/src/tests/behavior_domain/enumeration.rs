//! 旅行者の歩行を数え上げる領域が、有限に数え上げられる領域として答える実装。
//!
//! 親のファイルから分けるのは、親が持つのは領域そのものの組み立てと探索の起動であり、こちらが持つのは
//! 検証の語彙(数え上げ・遷移の帰結・設計概念への参照)との対応だけであるためである(CLAUDE.md「切り出しの根拠義務」の1号)。
//!
//! `一回遷移する` は `旅行者の現在地::歩行を遷移する` をそのまま呼ぶ。遷移の意味をこの試験の側へ1行も書き写さないのは、
//! 書き写すと検証の入口がゲームロジックを再実装したことになるためである(Issue #173 が禁じた形)。
//!
//! 状態の同一性を `現在地のビット表現` で答え、名指しも同じ写しから名前を導く。源を1つにするのは、名指しだけが丸めていると、
//! 探索が別物として残した状態を命題の層が同じ1件として引き当てられるためである(PR #177 のBlocker B)。
//!
//! コマンドの数え上げが `連続量を含む標本` で答えるのは、`旅行者の意図::歩く` が持つ `歩行方向` が単精度2成分の連続量であり、
//! 取りうる値を全部並べられないためである。これを `全件` と偽らないことがIssue #174のオーナー裁定の核心である。

use blitz_design_verification::{数え上げ, 有限に数え上げられる領域, 設計概念への参照, 遷移の帰結};

use super::旅行者の歩行を数え上げる領域;
use crate::tests::behavior_identity::現在地のビット表現;
use crate::tests::behavior_landmark::{移動可能範囲の内側と同じマスに載る現在地, 移動可能範囲の内側の現在地, 移動可能範囲の東の端の現在地};
use crate::tests::behavior_naming::{旅行者の出来事を名指す, 旅行者の意図を名指す, 旅行者の現在地を名指す, 歩行遷移の規則を名指す};
use crate::traveler::{旅行者の出来事, 旅行者の意図, 旅行者の現在地};
use crate::walking_direction::歩行方向;

impl 有限に数え上げられる領域 for 旅行者の歩行を数え上げる領域 {
    type 状態 = 旅行者の現在地;
    type コマンド = 旅行者の意図;
    type 出来事 = 旅行者の出来事;
    type 状態の同一性 = 現在地のビット表現;

    /// 東の端と移動可能範囲の内側と、内側と同じマスに載る現在地の3つから探索を始める。
    /// 端が代表ケースの前状態であり、内側が偽の命題の反例の前状態であり、3つ目が名指しの丸めを見るための現在地である。
    /// 全件でなく標本で答えるのは、現在地の東と北が単精度2成分の連続量であり、取りうる初期状態を全部は並べられないためである。
    /// この3つを「代表ケース」と呼んだまま全件として扱うと、見ていない初期状態についての全称が証明済みになる(Major F)。
    fn 初期状態を数え上げる(&self) -> 数え上げ<旅行者の現在地> {
        数え上げ::連続量を含む標本 {
            標本: vec![移動可能範囲の東の端の現在地(), 移動可能範囲の内側の現在地(), 移動可能範囲の内側と同じマスに載る現在地()],
            連続量の説明: "旅行者の現在地 は単精度2成分の連続量であり、初期状態は代表の3点に限る".to_string(),
        }
    }

    /// 標本は静止・見回すと、軸に沿う東西南北の4方向の歩くの、あわせて6件である。
    fn 状態で試すコマンドを数え上げる(&self, _状態: &旅行者の現在地) -> 数え上げ<旅行者の意図> {
        数え上げ::連続量を含む標本 {
            標本: vec![
                旅行者の意図::静止,
                旅行者の意図::見回す,
                旅行者の意図::歩く { 方向: 歩行方向::東() },
                旅行者の意図::歩く { 方向: 歩行方向::西() },
                旅行者の意図::歩く { 方向: 歩行方向::北() },
                旅行者の意図::歩く { 方向: 歩行方向::南() },
            ],
            連続量の説明: "歩行方向 は単精度2成分の連続量であり、標本は軸に沿う4方向に限る".to_string(),
        }
    }

    /// 実物の遷移関数を呼ぶ。座標が有限でなくなる失敗は帰結の失敗へ写し、次の状態も出来事も採用しない。失敗のときは遷移失敗結果の元の状態をそのまま帰結へ入れ、受け取った状態との等しさは探索が確かめる。
    /// 遷移は状態を値で受け取るため、探索がたどった前の状態を覚えておけるよう、検証の側だけが複製を作って渡す。
    /// `旅行者の現在地` は `Copy` であり、参照外しの `*状態` がその複製である(`.clone()` と書くと clippy の `clone_on_copy` が退ける)。
    fn 一回遷移する(&self, 状態: &旅行者の現在地, コマンド: &旅行者の意図) -> 遷移の帰結<旅行者の現在地, 旅行者の出来事> {
        match (*状態).歩行を遷移する(コマンド, &self.規則, self.パラメータ) {
            Ok(成功) => 遷移の帰結::成功 {
                次の状態: 成功.次の状態,
                出来事一覧: 成功.出来事一覧,
            },
            Err(失敗) => 遷移の帰結::失敗 {
                元の状態: 失敗.元の状態,
                説明: 失敗.失敗の理由.to_string(),
            },
        }
    }

    /// 同一性を単精度のビットの並びで取る。名指しもこの写しから名前を導くため、探索の済みの判断と命題の名指しが同じ源を持つ。
    fn 状態の同一性を答える(&self, 状態: &旅行者の現在地) -> 現在地のビット表現 {
        現在地のビット表現::現在地から写す(状態)
    }

    fn 状態を名指す(&self, 状態: &旅行者の現在地) -> 設計概念への参照 {
        旅行者の現在地を名指す(状態)
    }

    fn コマンドを名指す(&self, コマンド: &旅行者の意図) -> 設計概念への参照 {
        旅行者の意図を名指す(コマンド)
    }

    fn 出来事を名指す(&self, 出来事: &旅行者の出来事) -> 設計概念への参照 {
        旅行者の出来事を名指す(出来事)
    }

    fn 規則を名指す(&self) -> 設計概念への参照 {
        歩行遷移の規則を名指す()
    }
}
