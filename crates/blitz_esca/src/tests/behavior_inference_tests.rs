//! 排他の推論規則がドメインの法則を1つ導くことと、前提の弱さを結論へ引き継ぐことを固定する試験(Issue #174)。
//!
//! `旅行者の出来事` は周囲を観察したと障害物に遮られたの2つしかなく、前者は見回す意図の遷移でだけ生じ、
//! 後者は歩く意図の遷移でだけ生じる。したがって2つが同時に成立しないことは実在する排他の法則である。
//! この規則は、代表ケースの正の命題の成立から「その遷移では周囲を観察したが発生しない」を導く。
//! ただし正の命題は連続量の標本に限る網羅性のため未決定であり、前提が成立しないなら結論も未決定になる。
//! これは推論規則が前提の弱さを引き継ぐことの確認であり、望ましい振る舞いである。

#![allow(clippy::unwrap_used)]

use blitz_design_verification::{未決定の理由, 検証結果};

use super::behavior_domain::旅行者の歩行を数え上げる領域;
use super::behavior_landmark::移動可能範囲の東の端の現在地;
use super::behavior_proposition::旅行者の歩行の命題を組む工程;

#[test]
fn 排他の推論規則は代表ケースの正の命題から周囲を観察したの不発生を結論に持つ() {
    let 領域 = 旅行者の歩行を数え上げる領域::生成する();
    let 工程 = 旅行者の歩行の命題を組む工程::生成する(領域.マスの一辺());
    let 正の命題 = 工程.端から範囲の外へ歩くと障害物に遮られる命題を組む(&移動可能範囲の東の端の現在地());
    let 推論規則 = 工程.障害物と観察の排他の推論規則を組む().推論規則へ写す(&正の命題).unwrap();
    let 結論の表記 = 推論規則.結論().表記();
    assert!(結論の表記.contains("NOT"), "結論が否定の形になっていない: {結論の表記}");
    assert!(結論の表記.contains("周囲を観察した"), "結論が周囲を観察したについて言っていない: {結論の表記}");
}

#[test]
fn 前提が未決定である排他の推論規則の結論は証明済みへ格上げされず未決定になる() {
    let 領域 = 旅行者の歩行を数え上げる領域::生成する();
    let 工程 = 旅行者の歩行の命題を組む工程::生成する(領域.マスの一辺());
    let 正の命題 = 工程.端から範囲の外へ歩くと障害物に遮られる命題を組む(&移動可能範囲の東の端の現在地());
    let 推論規則 = 工程.障害物と観察の排他の推論規則を組む().推論規則へ写す(&正の命題).unwrap();
    match 推論規則.前提から結論を導く(&領域.検証器を組む()) {
        検証結果::未決定(未決定の理由::推論規則の前提が成立していない(説明)) => {
            assert!(説明.contains("未決定"), "前提が成立しない理由に前提の結末が入っていない: {説明}");
        }
        それ以外 => panic!("未決定の前提から結論が導かれてしまった: {}", それ以外.表記()),
    }
}
