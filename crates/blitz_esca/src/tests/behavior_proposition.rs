//! 旅行者の歩行についての振る舞いの命題の組み立て(Issue #174)。
//!
//! 命題の形をこの1箇所へ閉じるのは、量化した遷移を指す束縛と、その束縛を使う原子と、前件が名指す現在地の表記が
//! 揃っていなければ命題が意味を持たないためである。前件の表記が1文字違えば、含意は前件が偽で常に成立し、検証が黙って空虚に通る。
//! マスの一辺を保持するのは、現在地の名前がその一辺に依るためであり、領域そのものを受け取らないのは、
//! 領域を丸ごと受け取る工程が工程の分離にならないためである(CLAUDE.md「切り出しの根拠義務」)。

use blitz_design_verification::{原子命題, 命題, 対象集合, 排他の推論規則, 束縛変数, 設計概念の識別子, 項};

use super::behavior_naming::{旅行者の出来事を名指す, 旅行者の意図を名指す, 現在地を名指すマスの一辺};
use crate::traveler::{旅行者の出来事, 旅行者の意図, 旅行者の現在地};
use crate::walking_direction::歩行方向;

/// 1件の遷移を名指す3つ組。3つがどれも設計概念の識別子であり、引数として並べると取り違えても型が通るため名前付きの束にする。
struct 名指した遷移の3つ組 {
    前状態: 設計概念の識別子,
    入力: 設計概念の識別子,
    後状態: 設計概念の識別子,
}

/// 旅行者の歩行の命題を組む工程。
pub struct 旅行者の歩行の命題を組む工程 {
    マスの一辺: 現在地を名指すマスの一辺,
}

impl 旅行者の歩行の命題を組む工程 {
    pub fn 生成する(マスの一辺: 現在地を名指すマスの一辺) -> Self {
        Self { マスの一辺 }
    }

    /// 移動可能範囲の端から範囲の外へ歩く遷移では障害物に遮られたが発生する、という代表ケースの命題。
    /// 境界に収められた結果として後状態が前状態と同じマスになるため、3つ組の前状態と後状態は同じ識別子である。
    pub fn 端から範囲の外へ歩くと障害物に遮られる命題を組む(&self, 東の端の現在地: &旅行者の現在地) -> 命題 {
        self.全称の含意を組む(
            名指した遷移の3つ組 {
                前状態: self.マスの一辺.現在地を名指す(東の端の現在地),
                入力: 旅行者の意図を名指す(&旅行者の意図::歩く { 方向: 歩行方向::東() }),
                後状態: self.マスの一辺.現在地を名指す(東の端の現在地),
            },
            旅行者の出来事::障害物に遮られた,
        )
    }

    /// 移動可能範囲の内側を東へ歩く遷移でも障害物に遮られたが発生する、という偽の命題。
    /// 内側の遷移は境界に当たらないため出来事を1件も生成せず、この遷移そのものが本物の反例になる。
    pub fn 内側を東へ歩いても障害物に遮られるという偽の命題を組む(&self, 内側の現在地: &旅行者の現在地, 東へ歩いた先の現在地: &旅行者の現在地) -> 命題 {
        self.全称の含意を組む(
            名指した遷移の3つ組 {
                前状態: self.マスの一辺.現在地を名指す(内側の現在地),
                入力: 旅行者の意図を名指す(&旅行者の意図::歩く { 方向: 歩行方向::東() }),
                後状態: self.マスの一辺.現在地を名指す(東へ歩いた先の現在地),
            },
            旅行者の出来事::障害物に遮られた,
        )
    }

    /// 名指した1件の遷移で障害物に遮られたが発生する、という偽の命題。量化で包まないのは、
    /// 全称の反例が残す再現の材料が束縛の割り当てであり、遷移1件の前状態・入力・得られた出来事を見るには原子のまま問う必要があるためである。
    pub fn その遷移で障害物に遮られたが発生する命題を組む(&self, 遷移の概念: 設計概念の識別子) -> 命題 {
        命題::原子から組む(原子命題::発生する {
            遷移: 項::名指した概念(遷移の概念),
            イベント: 項::名指した概念(旅行者の出来事を名指す(&旅行者の出来事::障害物に遮られた)),
        })
    }

    /// 到達可能な状態が1つ在る、という存在の命題。標本の中の証人は本物の証人である。
    pub fn 到達可能な状態が1つ在る命題を組む(&self) -> 命題 {
        let 量化した状態 = 束縛変数::生成する("状態");
        命題::存在を組む(量化した状態.clone(), 対象集合::到達可能な状態, 命題::原子から組む(原子命題::到達可能である { 状態: 項::束縛変数(量化した状態) }))
    }

    /// 名指した現在地が到達可能である、という命題。証人が無い現在地を名指して問うために使う。
    pub fn その現在地が到達可能である命題を組む(&self, 現在地: &旅行者の現在地) -> 命題 {
        命題::原子から組む(原子命題::到達可能である {
            状態: 項::名指した概念(self.マスの一辺.現在地を名指す(現在地)),
        })
    }

    /// 障害物に遮られたと周囲を観察したが同時に成立しないという排他の推論規則。
    /// 前者は歩く意図の遷移でだけ生じ、後者は見回す意図の遷移でだけ生じるため、これは実在する排他の法則である。
    pub fn 障害物と観察の排他の推論規則を組む(&self) -> 排他の推論規則 {
        排他の推論規則::生成する(旅行者の出来事を名指す(&旅行者の出来事::障害物に遮られた), 旅行者の出来事を名指す(&旅行者の出来事::周囲を観察した))
    }

    // 到達可能な遷移を量化し、3つ組で名指した遷移ならその出来事が発生すると言う含意を組む。
    fn 全称の含意を組む(&self, 名指した3つ組: 名指した遷移の3つ組, 後件の出来事: 旅行者の出来事) -> 命題 {
        let 量化した遷移 = 束縛変数::生成する("遷移");
        命題::全称を組む(
            量化した遷移.clone(),
            対象集合::到達可能な遷移,
            命題::含意を組む(
                命題::原子から組む(原子命題::遷移する {
                    前状態: 項::名指した概念(名指した3つ組.前状態),
                    入力: 項::名指した概念(名指した3つ組.入力),
                    後状態: 項::名指した概念(名指した3つ組.後状態),
                }),
                命題::原子から組む(原子命題::発生する {
                    遷移: 項::束縛変数(量化した遷移),
                    イベント: 項::名指した概念(旅行者の出来事を名指す(&後件の出来事)),
                }),
            ),
        )
    }
}
