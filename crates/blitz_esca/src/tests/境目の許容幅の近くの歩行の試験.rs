//! 境目の許容幅の近くで壁を越えようとした歩行が、旅行者を区域の閉包の外へ着かせないことを固定する試験(Issue #187 の作業G2)。
//!
//! 境界の上とみなす許容幅は、座標の大きさの2の20乗分の1である(座標1000メートルで約0.95ミリメートル)。
//! 壁を越えた長さが許容幅の半分より長く1倍より短いとき、越えた区間の中点は境界の上と判断される。この試験は、そのときも旅行者が壁の外に着かないこと、
//! および着いた後の刻みの遷移が失敗しないこと(失敗すると旅の一刻みが元の居場所を保ち、旅行者が二度と動けない)を固定する。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::expect_used)]

use blitz_math::{メートル毎秒, 大域メートル};

use super::一つの区域の試料::{一つの区域の広場, 現在地, 経過, 長方形の端};
use crate::traveler::{旅行者の意図, 歩行の規則};
use crate::traveler_input::キーボード歩行入力;
use crate::traveler_movement::歩行遷移の規則;
use crate::walking_direction::歩行方向;
use crate::居場所::旅行者の居場所;

const 越える長さの許容幅に対する比一覧: [f64; 7] = [0.25, 0.5, 0.75, 1.0, 1.5, 2.0, 3.0]; // 0.5・1・2倍に、その間と外側を足す
const 座標の大きさ一覧: [f32; 2] = [100.0, 1000.0];

#[test]
fn 壁を許容幅の半分より長く1倍より短く越えた歩行でも旅行者は閉包の外に着かず次の刻みも遷移できる() {
    let 広場 = 長方形の端 {
        東の最小: 0.0,
        東の最大: 1000.0,
        北の最小: 0.0,
        北の最大: 1000.0,
    };
    let 規則 = 広場.歩行の規則を組む(歩行の規則::生成する(メートル毎秒::生成する(0.05)).expect("有限な0以上の速さは規則になるべきである"));
    // 999.9514 から東へ 0.05 メートル進んだ目的地は 1000.0014 であり、東の壁(1000)を約1.4ミリメートル越える。許容幅は約0.95ミリメートルである。
    let 着いた = 広場
        .広場の居場所(現在地(999.9514, 500.0))
        .歩行を遷移する(&旅行者の意図::歩く { 方向: 歩行方向::東() }, &規則, 経過(1.0))
        .expect("区域の中から歩く遷移は成功するべきである");
    let 許容幅 = 1000.0 / 1_048_576.0;
    assert!(f64::from(着いた.次の状態.現在地().東().値()) <= 1000.0 + 許容幅, "旅行者が東の壁の外に着いた: {:?}", 着いた.次の状態.現在地());
    let 次の刻み = 着いた.次の状態.clone().歩行を遷移する(&旅行者の意図::静止, &規則, 経過(1.0));
    assert!(次の刻み.is_ok(), "着いた後の静止の遷移が失敗した: {:?}", 次の刻み.err().map(|失敗| 失敗.失敗の理由));
}

#[test]
fn 許容幅の窓のどの越え方でも軸に揃った壁と斜めの壁で旅行者は閉包の中に着き以後の刻みも遷移できる() {
    for 大きさ in 座標の大きさ一覧 {
        for 比 in 越える長さの許容幅に対する比一覧 {
            軸に揃った壁の場面(大きさ, 比).確かめる();
            斜めの壁の場面(大きさ, 比).確かめる();
        }
    }
}

// 壁へ向かって、壁までの距離より許容幅の比の倍だけ長く歩く場面。着いた後に、静止・壁に沿う歩行・もう一度壁へ向かう歩行・壁から離れる歩行を続ける。
struct 壁へ歩く場面 {
    題: String,
    広場: 一つの区域の広場,
    始点: (f32, f32),
    壁へ向かう方向: 歩行方向,
    壁に沿う方向: 歩行方向,
    壁から離れる方向: 歩行方向,
    速さ: f32,
}

// 東の壁が座標の大きさにある正方形。壁の1メートル手前の中ほどから東へ歩く。
fn 軸に揃った壁の場面(大きさ: f32, 比: f64) -> 壁へ歩く場面 {
    let 許容幅 = f64::from(大きさ) / 1_048_576.0;
    壁へ歩く場面 {
        題: format!("軸に揃った壁 座標{大きさ} 越え方{比}"),
        広場: 一つの区域の広場::頂点から作る(&[(0.0, 0.0), (大きさ, 0.0), (大きさ, 大きさ), (0.0, 大きさ)]),
        始点: (大きさ - 1.0, 大きさ / 2.0),
        壁へ向かう方向: 歩行方向::東(),
        壁に沿う方向: 歩行方向::北(),
        壁から離れる方向: 歩行方向::西(),
        速さ: 単精度の速さ(1.0 + 比 * 許容幅),
    }
}

// 斜めの壁(東と北の和が座標の大きさの2倍の直線)を持つ三角形。壁から√2メートル手前の点から北東へ歩く。
fn 斜めの壁の場面(大きさ: f32, 比: f64) -> 壁へ歩く場面 {
    let 許容幅 = f64::from(大きさ) / 1_048_576.0;
    let 斜め = |入力: キーボード歩行入力| 歩行方向::キー入力から導く(&入力).expect("斜めのキー入力は向きになる");
    壁へ歩く場面 {
        題: format!("斜めの壁 座標{大きさ} 越え方{比}"),
        広場: 一つの区域の広場::頂点から作る(&[(0.0, 0.0), (大きさ * 2.0, 0.0), (0.0, 大きさ * 2.0)]),
        始点: (大きさ - 1.0, 大きさ - 1.0),
        壁へ向かう方向: 斜め(キーボード歩行入力 { 上: true, 右: true, ..Default::default() }),
        壁に沿う方向: 斜め(キーボード歩行入力 { 上: true, 左: true, ..Default::default() }),
        壁から離れる方向: 斜め(キーボード歩行入力 { 下: true, 左: true, ..Default::default() }),
        速さ: 単精度の速さ(std::f64::consts::SQRT_2 + 比 * 許容幅),
    }
}

// 倍精度で求めた速さを、最も近い単精度の値へ狭める。
fn 単精度の速さ(速さ: f64) -> f32 {
    大域メートル::生成する(速さ).メートルへ狭める().expect("1メートル毎秒ほどの速さは単精度で表せる").値()
}

impl 壁へ歩く場面 {
    fn 確かめる(&self) {
        let 規則 = self.広場.歩行の規則を組む(歩行の規則::生成する(メートル毎秒::生成する(self.速さ)).expect("有限な0以上の速さは規則になるべきである"));
        let mut 居場所 = self.広場.広場の居場所(現在地(self.始点.0, self.始点.1));
        let 歩く = |方向: &歩行方向| 旅行者の意図::歩く { 方向: *方向 };
        let 意図の並び = [歩く(&self.壁へ向かう方向), 旅行者の意図::静止, 歩く(&self.壁に沿う方向), 歩く(&self.壁へ向かう方向), 歩く(&self.壁から離れる方向)];
        for (番号, 意図) in 意図の並び.iter().enumerate() {
            居場所 = self.一刻み歩いて閉包の中にあることを確かめる(居場所, 意図, &規則, 番号);
        }
    }

    fn 一刻み歩いて閉包の中にあることを確かめる(&self, 居場所: 旅行者の居場所, 意図: &旅行者の意図, 規則: &歩行遷移の規則, 番号: usize) -> 旅行者の居場所 {
        let 次の居場所 = match 居場所.歩行を遷移する(意図, 規則, 経過(1.0)) {
            Ok(成功) => 成功.次の状態,
            Err(失敗) => panic!("{}: {番号}番目の刻み({意図:?})の遷移が失敗した: {:?}", self.題, 失敗.失敗の理由),
        };
        let 点 = 次の居場所.現在地().平面の点へ広げる();
        assert!(self.広場.区域.多角形().閉包に入るか(&点), "{}: {番号}番目の刻み({意図:?})で閉包の外に着いた: {点:?}", self.題);
        次の居場所
    }
}
