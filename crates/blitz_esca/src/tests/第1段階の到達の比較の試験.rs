//! 第1段階の歩行の有限全数の検証を、長方形の移動可能範囲から1つの区域へ表し直しても、到達する状態が変わらないことを確かめる一時の試験(Issue #187 の作業G2)。
//!
//! 長方形の側は、第1段階の実物の `移動可能範囲::制限する` で目的地を範囲へ収める幅優先の探索で到達する現在地を集める。
//! 区域の側は、1つの区域で表し直した領域(`旅行者の歩行を数え上げる領域`)の探索が組んだ遷移モデルの到達可能な状態である。
//! 2つの初期状態と意図の標本は同じである。この試験は移動可能範囲を消すコミットで一緒に消す(比べる相手が無くなるため)。

#![allow(clippy::expect_used)]

use std::collections::VecDeque;

use blitz_math::{メートル, 秒};

use super::behavior_domain::旅行者の歩行を数え上げる領域;
use super::behavior_landmark::{移動可能範囲の内側と同じマスに載る現在地, 移動可能範囲の内側の現在地, 移動可能範囲の東の端の現在地, 移動可能範囲の端のメートル};
use super::behavior_naming::旅行者の現在地を名指す;
use crate::traveler::{旅行者の現在地, 歩行の規則, 移動の変位};
use crate::traveler_boundary::移動可能範囲の指定;
use crate::walking_direction::歩行方向;

// 長方形の移動可能範囲の中を、第1段階の遷移と同じ目的地の求め方と実物の範囲への収め方で幅優先に辿り、到達した現在地を並べる。
fn 長方形の範囲で到達する現在地一覧() -> Vec<旅行者の現在地> {
    let 範囲 = 移動可能範囲の指定 {
        東の最小: メートル::生成する(0.0),
        東の最大: メートル::生成する(移動可能範囲の端のメートル),
        北の最小: メートル::生成する(0.0),
        北の最大: メートル::生成する(移動可能範囲の端のメートル),
    }
    .検証する()
    .expect("最小が最大以下の範囲");
    let 速さ = 歩行の規則::標準().速さ();
    let mut 到達した: Vec<旅行者の現在地> = Vec::new();
    let mut 待ち行列: VecDeque<旅行者の現在地> = [移動可能範囲の東の端の現在地(), 移動可能範囲の内側の現在地(), 移動可能範囲の内側と同じマスに載る現在地()].into_iter().collect();
    while let Some(現在地) = 待ち行列.pop_front() {
        if 到達した.contains(&現在地) {
            continue;
        }
        到達した.push(現在地);
        for 方向 in [歩行方向::東(), 歩行方向::西(), 歩行方向::北(), 歩行方向::南()] {
            let 目的地 = 現在地
                .平行移動する(移動の変位 {
                    東: 速さ.比で伸ばす(方向.東の比率()) * 秒::生成する(1.0),
                    北: 速さ.比で伸ばす(方向.北の比率()) * 秒::生成する(1.0),
                })
                .expect("有限な目的地");
            let 収めた = 範囲.制限する(目的地);
            待ち行列.push_back(旅行者の現在地::生成する(収めた.制限後の東, 収めた.制限後の北).expect("有限な現在地"));
        }
    }
    到達した
}

#[test]
fn 長方形の範囲と1つの区域で到達する現在地が一致する() {
    let 長方形の側 = 長方形の範囲で到達する現在地一覧();
    let 区域の側 = 旅行者の歩行を数え上げる領域::生成する().遷移モデルと網羅性を組む().モデル.到達可能な状態一覧を組む();
    assert_eq!(長方形の側.len(), 区域の側.件数(), "到達する状態の件数が変わった");
    for 現在地 in &長方形の側 {
        assert!(区域の側.含むか(&旅行者の現在地を名指す(現在地)), "長方形の範囲で到達する {現在地:?} に区域の側で到達しない");
    }
}
