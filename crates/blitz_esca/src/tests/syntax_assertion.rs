//! Escaオントロジーの構文検証説明関数群(Issue #137)。
//!
//! テストコードから低水準な探索照合ロジックを排し、
//! 設計規則の意図を明示したメソッドチェーン可能な高水準アサーションを提供する。

use crate::ontology::{オントロジー関数型, オントロジートレイト};
use super::syntax_checker::クレート構文検査;
use super::syntax_patterns::Rust型種別;

impl<'a> クレート構文検査<'a> {
    pub fn すべてのコマンドが列挙型であること(self) -> Self {
        for 型 in self.トレイト実装型一覧(オントロジートレイト::Mコマンド) {
            assert!(self.型種別を満たしているか(Rust型種別::列挙型, 型), "Mコマンド `{型}` はenum定義が必要です");
        }
        self
    }

    pub fn すべての規則が構造体であること(self) -> Self {
        for 型 in self.トレイト実装型一覧(オントロジートレイト::M規則) {
            assert!(self.型種別を満たしているか(Rust型種別::構造体, 型), "M規則 `{型}` はstruct定義が必要です");
        }
        self
    }

    pub fn すべての状態がmdtoを実装していること(self) -> Self {
        for 型 in self.トレイト実装型一覧(オントロジートレイト::M状態) {
            assert!(self.トレイトを実装しているか(型, オントロジートレイト::MDTO), "M状態 `{型}` はMDTO実装が必要です");
        }
        self
    }

    pub fn すべての入力がmdtoを実装していること(self) -> Self {
        for 型 in self.トレイト実装型一覧(オントロジートレイト::M入力) {
            assert!(self.トレイトを実装しているか(型, オントロジートレイト::MDTO), "M入力 `{型}` はMDTO実装が必要です");
        }
        self
    }

    pub fn すべてのmdtoが純粋データ規約を満たすこと(self) -> Self {
        for 型 in self.トレイト実装型一覧(オントロジートレイト::MDTO) {
            let 違反 = self.dto純粋性違反一覧(型);
            assert!(違反.is_empty(), "MDTO `{型}` の純粋性違反: {:?}", 違反);
        }
        self
    }

    pub fn すべてのイベントが純粋データ規約を満たすこと(self) -> Self {
        for 型 in self.トレイト実装型一覧(オントロジートレイト::Mイベント) {
            let 違反 = self.dto純粋性違反一覧(型);
            assert!(違反.is_empty(), "Mイベント `{型}` の純粋性違反: {:?}", 違反);
        }
        self
    }

    pub fn m遷移関数の型引数がオントロジーを満たすこと(self) -> Self {
        let 一覧 = self.宣言の型引数一覧(オントロジー関数型::M遷移関数);
        assert!(!一覧.is_empty(), "M遷移関数の静的宣言が必要です");
        for 引 in &一覧 {
            assert_eq!(引.len(), 4, "M遷移関数は4つの型引数が必要です");
            let (状態, コマンド, 規則, イベント) = (&引[0], &引[1], &引[2], &引[3]);
            assert!(self.トレイトを実装しているか(状態, オントロジートレイト::M状態), "状態 `{状態}` が M状態 未実装");
            assert!(self.トレイトを実装しているか(コマンド, オントロジートレイト::Mコマンド), "コマンド `{コマンド}` が Mコマンド 未実装");
            assert!(self.トレイトを実装しているか(規則, オントロジートレイト::M規則), "規則 `{規則}` が M規則 未実装");
            assert!(self.トレイトを実装しているか(イベント, オントロジートレイト::Mイベント), "出来事 `{イベント}` が Mイベント 未実装");
        }
        self
    }

    pub fn m射影関数の型引数がオントロジーを満たすこと(self) -> Self {
        let 一覧 = self.宣言の型引数一覧(オントロジー関数型::M射影関数);
        assert!(!一覧.is_empty(), "M射影関数の静的宣言が必要です");
        for 引 in &一覧 {
            assert_eq!(引.len(), 2, "M射影関数は2つの型引数が必要です");
            let (状態, 射影dto) = (&引[0], &引[1]);
            assert!(self.トレイトを実装しているか(状態, オントロジートレイト::M状態), "状態 `{状態}` が M状態 未実装");
            assert!(self.トレイトを実装しているか(射影dto, オントロジートレイト::MDTO), "射影DTO `{射影dto}` が MDTO 未実装");
        }
        self
    }

    pub fn m解釈関数の型引数がオントロジーを満たすこと(self) -> Self {
        let 一覧 = self.宣言の型引数一覧(オントロジー関数型::M解釈関数);
        assert!(!一覧.is_empty(), "M解釈関数の静的宣言が必要です");
        for 引 in &一覧 {
            assert_eq!(引.len(), 2, "M解釈関数は2つの型引数が必要です");
            let (入力, コマンド) = (&引[0], &引[1]);
            assert!(self.トレイトを実装しているか(入力, オントロジートレイト::M入力), "入力 `{入力}` が M入力 未実装");
            assert!(self.トレイトを実装しているか(コマンド, オントロジートレイト::Mコマンド), "コマンド `{コマンド}` が Mコマンド 未実装");
        }
        self
    }

    pub fn 可変参照メソッドを一切含まないこと(self) -> Self {
        assert!(!self.可変参照メソッドを含むか(), "オントロジー構成要素は &mut self メソッドを持てません");
        self
    }
}
