//! 経路の開閉の状態を規則からしか作れないことと、別の地図の規則から作った状態を遷移させても地図の外の経路を持ったまま成功しないことを固定する試験(Issue #187 の作業G1)。
//!
//! 状態を地図を外から受けて作る口があると、別の地図で確かめた状態を作れる。遷移が命令の経路しか規則の地図と照らさなければ、その状態は地図の外の経路を持ったまま遷移に成功する。
//! この試験は、状態を作る口が規則だけであることと、遷移が状態の閉じている経路も規則の地図と照らすことの両方を、別の地図の規則から作った状態で確かめる。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::expect_used)]

use super::地点と経路の試料::{刻み, 地図の外の経路, 経路を指す, 試験の地図を組む, 試験の規則を組む, 隠し道だけの地図を組む};
use crate::地点と経路::{経路の指定の失敗, 経路の開閉の命令, 経路の開閉の規則};

#[test]
fn はじめの状態は予定がはじめに閉じている関所だけを閉じている() {
    let 閉じている一覧: Vec<_> = 試験の規則を組む().はじめの状態().閉じている経路一覧().cloned().collect();
    assert_eq!(閉じている一覧, vec![経路を指す(&試験の地図を組む(), "関所")]);
}

#[test]
fn 反例i_地図に無い経路を閉じている状態は規則から作れない() {
    let 橋 = 経路を指す(&試験の地図を組む(), "橋");
    let 失敗 = 試験の規則を組む().閉じている経路を確かめて状態を作る(vec![橋, 地図の外の経路()]).expect_err("地図に無い経路を含む状態は拒まれるべきである");
    assert_eq!(失敗, 経路の指定の失敗::地図に無い経路を指した { 経路: 地図の外の経路() });
}

#[test]
fn 反例i_別の地図の規則で作った状態は地図の外の経路を理由に遷移に失敗し受け取った状態を返す() {
    let 隠し道の規則 = 経路の開閉の規則::生成する(隠し道だけの地図を組む());
    let 別の地図の状態 = 隠し道の規則.閉じている経路を確かめて状態を作る(vec![地図の外の経路()]).expect("隠し道の地図では隠し道を閉じた状態を作れるべきである");
    let 橋 = 経路を指す(&試験の地図を組む(), "橋");
    for 命令 in [経路の開閉の命令::命令が無い, 経路の開閉の命令::経路を閉じる { 経路: 橋 }] {
        let 失敗 = 別の地図の状態
            .clone()
            .開閉を遷移する(&命令, &試験の規則を組む(), 刻み(0.0, 1.0))
            .expect_err("地図の外の経路を閉じている状態の遷移は失敗するべきである");
        assert_eq!(失敗.元の状態, 別の地図の状態, "失敗のとき受け取った状態が書き換わっている");
        assert_eq!(失敗.失敗の理由, 経路の指定の失敗::地図に無い経路を指した { 経路: 地図の外の経路() });
    }
}
