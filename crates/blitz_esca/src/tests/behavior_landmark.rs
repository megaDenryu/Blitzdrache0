//! 旅行者の歩行の検証が名指す、移動可能範囲の端と代表の現在地(Issue #174)。
//!
//! 領域の型から分けるのは、領域が持つのが有限に数え上げられる領域の契約の実装と遷移の規則であり、
//! こちらが持つのがその範囲の中で位置の決まった現在地だからである。どの現在地も領域のフィールドを1度も読まないため、
//! 状態を持たない処理を型のメソッドへ置かず自由関数で持つ(参照: グローバルCLAUDE.md「Rustの書き方の選択」条5(a))。
//! 移動可能範囲の端をこのモジュールが持つのは、東の端の現在地の東がその値に載り、領域の組み立てと同じ数を読むためである。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use crate::traveler::旅行者の現在地;

/// 移動可能範囲の東と北の最大。最小は0であり、東の端の現在地の東がこの値に載る。
pub const 移動可能範囲の端のメートル: f32 = 10.0;

// 東西の中央に当たる北の座標。どの代表の現在地も同じ北に立たせ、東西の違いだけが検証の結末を変えるようにする。
const 代表の現在地の北のメートル: f32 = 5.0;

/// 移動可能範囲の東の端に立つ現在地。ここから東へ歩くと範囲の外へ出ようとして境界に当たる。
pub fn 移動可能範囲の東の端の現在地() -> 旅行者の現在地 {
    旅行者の現在地::生成する(メートル::生成する(移動可能範囲の端のメートル), メートル::生成する(代表の現在地の北のメートル)).unwrap()
}

/// 移動可能範囲の内側に立つ現在地。ここから東へ歩いても範囲の外へ出ない。
pub fn 移動可能範囲の内側の現在地() -> 旅行者の現在地 {
    旅行者の現在地::生成する(メートル::生成する(5.0), メートル::生成する(代表の現在地の北のメートル)).unwrap()
}

/// 移動可能範囲の内側から東へ1回歩いた後の現在地。速さ3メートル毎秒と1秒の経過時間の積だけ東へ進んだ位置である。
pub fn 移動可能範囲の内側から東へ一回歩いた現在地() -> 旅行者の現在地 {
    旅行者の現在地::生成する(メートル::生成する(8.0), メートル::生成する(代表の現在地の北のメートル)).unwrap()
}

/// 移動可能範囲の外に在り、どの初期状態からも到達しない現在地。
pub fn 移動可能範囲の外の現在地() -> 旅行者の現在地 {
    旅行者の現在地::生成する(メートル::生成する(20.0), メートル::生成する(20.0)).unwrap()
}
