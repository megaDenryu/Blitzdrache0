//! 経路の開閉の遷移の反例を固定する試験(Issue #187 の作業G1)。
//!
//! 固定する反例は3つである。(i) 地図に無い経路を開く・閉じる命令は、状態を変えず遷移失敗結果として受け取った状態を返す(状態の作り方の反例は `経路の開閉の状態の作り方の試験.rs` が持つ)。
//! (ii) すでに閉じている経路を閉じる命令は、状態を変えず出来事も生まない(法則E2)。
//! (iii) 同じ刻みで時刻が閉じた経路を命令が開けば、命令が指す経路には予定を当てないため(出来事が勝つ。2026-09-26 オーナー裁定)経路は開いたまま残り、前後の開閉が同じなので出来事を生まない。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::expect_used)]

use super::地点と経路の試料::{刻み, 地図の外の経路, 峠道が閉じる秒, 峠道が開く秒, 経路を指す, 試験の地図を組む, 試験の規則を組む};
use crate::ontology::{遷移失敗結果, 遷移成功結果};
use crate::transition_parameter::遷移パラメータ;
use crate::地点と経路::{経路の指定の失敗, 経路の開閉, 経路の開閉の出来事, 経路の開閉の命令, 経路の開閉の状態};

type 開閉の遷移の結果 = Result<遷移成功結果<経路の開閉の状態, 経路の開閉の出来事>, 遷移失敗結果<経路の開閉の状態, 経路の指定の失敗>>;

fn 遷移させる(状態: 経路の開閉の状態, 命令: 経路の開閉の命令, パラメータ: 遷移パラメータ) -> 開閉の遷移の結果 {
    状態.開閉を遷移する(&命令, &試験の規則を組む(), パラメータ)
}

fn はじめの状態() -> 経路の開閉の状態 {
    試験の規則を組む().はじめの状態()
}

// 峠道の予定も時刻の予定も来ない、0秒から1秒までの刻み。
fn 予定の来ない刻み() -> 遷移パラメータ {
    刻み(0.0, 1.0)
}

#[test]
fn 反例i_地図に無い経路を閉じる命令も開く命令も受け取った状態を遷移失敗結果に入れて返す() {
    for 命令 in [経路の開閉の命令::経路を閉じる { 経路: 地図の外の経路() }, 経路の開閉の命令::経路を開く { 経路: 地図の外の経路() }] {
        let 失敗 = 遷移させる(はじめの状態(), 命令, 予定の来ない刻み()).expect_err("地図に無い経路を指す命令は失敗するべきである");
        assert_eq!(失敗.元の状態, はじめの状態(), "失敗のとき受け取った状態が書き換わっている");
        assert_eq!(失敗.失敗の理由, 経路の指定の失敗::地図に無い経路を指した { 経路: 地図の外の経路() });
    }
}

#[test]
fn 反例i_地図に無い経路を指す命令は同じ刻みに来た時刻の予定も当てない() {
    let 命令 = 経路の開閉の命令::経路を閉じる { 経路: 地図の外の経路() };
    let 失敗 = 遷移させる(はじめの状態(), 命令, 刻み(峠道が閉じる秒, 1.0)).expect_err("地図に無い経路を指す命令は失敗するべきである");
    assert_eq!(失敗.元の状態, はじめの状態(), "失敗した遷移が峠道の閉鎖を当てている");
}

#[test]
fn 反例ii_すでに閉じている経路を閉じる命令は状態を変えず出来事を生まない() {
    let 関所 = 経路を指す(&試験の地図を組む(), "関所");
    let 成功 = 遷移させる(はじめの状態(), 経路の開閉の命令::経路を閉じる { 経路: 関所 }, 予定の来ない刻み()).expect("地図に在る経路の命令は成功するべきである");
    assert_eq!(成功.次の状態, はじめの状態());
    assert!(成功.出来事一覧.is_empty(), "開閉が変わらないのに出来事が生じた: {:?}", 成功.出来事一覧);
}

#[test]
fn 開いている経路を閉じる命令は経路が閉じたを1件生む() {
    let 橋 = 経路を指す(&試験の地図を組む(), "橋");
    let 成功 = 遷移させる(はじめの状態(), 経路の開閉の命令::経路を閉じる { 経路: 橋.clone() }, 予定の来ない刻み()).expect("地図に在る経路の命令は成功するべきである");
    assert_eq!(成功.次の状態.経路の開閉(&橋), 経路の開閉::閉じている);
    assert_eq!(成功.出来事一覧, vec![経路の開閉の出来事::経路が閉じた { 経路: 橋 }]);
}

#[test]
fn 時間帯の始まりが来た刻みで経路が閉じ終わりが来た刻みで開く() {
    let 峠道 = 経路を指す(&試験の地図を組む(), "峠道");
    let 閉じた = 遷移させる(はじめの状態(), 経路の開閉の命令::命令が無い, 刻み(峠道が閉じる秒 - 0.5, 1.0)).expect("命令が無い遷移は成功するべきである");
    assert_eq!(閉じた.出来事一覧, vec![経路の開閉の出来事::経路が閉じた { 経路: 峠道.clone() }]);
    let 開いた = 遷移させる(閉じた.次の状態, 経路の開閉の命令::命令が無い, 刻み(峠道が開く秒, 1.0)).expect("命令が無い遷移は成功するべきである");
    assert_eq!(開いた.出来事一覧, vec![経路の開閉の出来事::経路が開いた { 経路: 峠道 }]);
    assert_eq!(開いた.次の状態, はじめの状態());
}

#[test]
fn 反例iii_同じ刻みで時刻が閉じた経路を命令が開けば開いたまま残り出来事を生まない() {
    let 峠道 = 経路を指す(&試験の地図を組む(), "峠道");
    let 成功 = 遷移させる(はじめの状態(), 経路の開閉の命令::経路を開く { 経路: 峠道.clone() }, 刻み(峠道が閉じる秒, 1.0)).expect("地図に在る経路の命令は成功するべきである");
    assert_eq!(成功.次の状態.経路の開閉(&峠道), 経路の開閉::開いている, "命令が指す経路に時刻の予定を当てている");
    assert!(成功.出来事一覧.is_empty(), "前後の開閉が同じなのに出来事が生じた: {:?}", 成功.出来事一覧);
}

#[test]
fn 同じ刻みで時刻と命令がどちらも閉じた経路の出来事は1件だけである() {
    let 峠道 = 経路を指す(&試験の地図を組む(), "峠道");
    let 成功 = 遷移させる(はじめの状態(), 経路の開閉の命令::経路を閉じる { 経路: 峠道.clone() }, 刻み(峠道が閉じる秒, 1.0)).expect("地図に在る経路の命令は成功するべきである");
    assert_eq!(成功.出来事一覧, vec![経路の開閉の出来事::経路が閉じた { 経路: 峠道 }]);
}

#[test]
fn 経過時間が0の刻みは始まりの時刻に来る予定も当てない() {
    let 成功 = 遷移させる(はじめの状態(), 経路の開閉の命令::命令が無い, 刻み(峠道が閉じる秒, 0.0)).expect("命令が無い遷移は成功するべきである");
    assert_eq!(成功.次の状態, はじめの状態());
    assert!(成功.出来事一覧.is_empty());
}
