//! 旅の1刻みの順序(開閉を遷移する → 通れる通り口を導く → 歩行を遷移する)が結果を決めることを固定する試験(Issue #187 の作業G2)。
//!
//! 峠道は10秒から20秒まで閉じる予定を持つ。村の(8, 5)から東へ3メートル歩く旅行者は、峠道が開いている刻みなら峠へ入る。
//! 峠道が閉じる時刻が来た刻み(10秒から11秒)では、開閉が先に遷移して峠道が閉じ、その後の歩行は閉じた峠道で遮られる。
//! あわせて、2つの遷移の失敗を独立に扱うこと(地図に無い経路の命令を拒んでも歩行は進む)を固定する。
//! 純粋な計算だけであり外部とのやり取りを持たないため、`tests/` へ実行ファイルを増やさず `src` の中に置く。

#![allow(clippy::expect_used)]

use super::一つの区域の試料::現在地;
use super::地点と経路の試料::{刻み, 地図の外の経路, 封鎖できる経路を指す, 峠道が閉じる秒, 試験の地図を組む, 試験の規則を組む};
use crate::traveler::{旅行者の出来事, 旅行者の意図, 歩行の規則};
use crate::walking_direction::歩行方向;
use crate::地点と経路::地点と経路の図式::地点Id;
use crate::地点と経路::{経路の開閉, 経路の開閉の出来事, 経路の開閉の命令};
use crate::居場所::旅行者の居場所;
use crate::旅の一刻み::{旅の一刻みの入力, 旅の一刻みの失敗, 旅の一刻みの結果, 旅の進行, 旅の進行の指定};

fn 村の居場所(東: f32, 北: f32) -> 旅行者の居場所 {
    旅行者の居場所::生成する(試験の地図を組む().地点を確かめる(&地点Id("村".to_string())).expect("村は試験の地図に在る"), 現在地(東, 北))
}

fn 東へ一刻み進める(命令: 経路の開閉の命令, 始まりの秒: f64) -> 旅の一刻みの結果 {
    let 規則 = 試験の規則を組む();
    let 進行 = 旅の進行::始める(旅の進行の指定 {
        開閉の状態: 規則.はじめの状態(),
        開閉の規則: 規則,
        居場所: 村の居場所(8.0, 5.0),
        身体: 歩行の規則::標準(),
    })
    .expect("規則のはじめの状態から進行を始められるべきである");
    進行.一刻み進める(
        &旅の一刻みの入力 {
            開閉の命令: 命令,
            旅行者の意図: 旅行者の意図::歩く { 方向: 歩行方向::東() },
        },
        刻み(始まりの秒, 1.0),
    )
}

#[test]
fn 峠道が開いている刻みでは峠道を通って峠へ入る() {
    let 結果 = 東へ一刻み進める(経路の開閉の命令::命令が無い, 峠道が閉じる秒 - 2.0);
    assert_eq!(結果.次の進行.居場所().地点().表記(), "峠");
    assert!(結果.開閉の出来事一覧.is_empty() && 結果.旅行者の出来事一覧.is_empty() && 結果.失敗一覧.is_empty());
}

#[test]
fn 峠道が閉じる刻みでは開閉が先に遷移し歩行は閉じた峠道で遮られる() {
    let 結果 = 東へ一刻み進める(経路の開閉の命令::命令が無い, 峠道が閉じる秒);
    let 峠道 = 封鎖できる経路を指す(&試験の地図を組む(), "峠道");
    assert_eq!(結果.開閉の出来事一覧, vec![経路の開閉の出来事::経路が閉じた { 経路: 峠道.clone() }]);
    assert_eq!(結果.次の進行.開閉の状態().経路の開閉(&峠道), 経路の開閉::閉じている);
    assert_eq!(結果.次の進行.居場所(), &村の居場所(10.0, 5.0), "閉じた峠道の手前の境目で止まるべきである");
    assert_eq!(結果.旅行者の出来事一覧, vec![旅行者の出来事::障害物に遮られた]);
    let 次の刻み = 結果.次の進行.一刻み進める(
        &旅の一刻みの入力 {
            開閉の命令: 経路の開閉の命令::命令が無い,
            旅行者の意図: 旅行者の意図::歩く { 方向: 歩行方向::東() },
        },
        刻み(峠道が閉じる秒 + 1.0, 1.0),
    );
    assert_eq!(次の刻み.次の進行.居場所(), &村の居場所(10.0, 5.0), "閉じた峠道は次の刻みでも通れない");
}

#[test]
fn 命令が峠道を閉じた刻みの歩行も閉じた峠道で遮られる() {
    let 峠道 = 封鎖できる経路を指す(&試験の地図を組む(), "峠道");
    let 結果 = 東へ一刻み進める(経路の開閉の命令::経路を閉じる { 経路: 峠道 }, 0.0);
    assert_eq!(結果.次の進行.居場所(), &村の居場所(10.0, 5.0));
}

#[test]
fn 地図に無い経路の命令を拒んでも歩行は進み開閉の状態は変わらない() {
    let 結果 = 東へ一刻み進める(経路の開閉の命令::経路を閉じる { 経路: 地図の外の経路() }, 0.0);
    assert!(matches!(結果.失敗一覧.as_slice(), [旅の一刻みの失敗::開閉を遷移できなかった(_)]), "{:?}", 結果.失敗一覧);
    assert_eq!(結果.次の進行.開閉の状態(), &試験の規則を組む().はじめの状態());
    assert_eq!(結果.次の進行.居場所().地点().表記(), "峠", "開閉の失敗に関わらず歩行は開いた峠道を通るべきである");
}
