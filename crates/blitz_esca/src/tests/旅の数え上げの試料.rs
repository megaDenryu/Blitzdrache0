/// 領域の状態。経路の開閉の状態と旅行者の居場所の組である。
#[derive(Debug, Clone, PartialEq)]
pub struct 旅の状態 {
    pub 開閉: 経路の開閉の状態,
    pub 居場所: 旅行者の居場所,
}

impl M不変データ for 旅の状態 {}
impl M状態 for 旅の状態 {}

/// 領域のコマンド。1刻みに与える開閉の命令と旅行者の意図の組である。
#[derive(Debug, Clone, PartialEq)]
pub enum 旅のコマンド {
    開閉と意図 { 命令: 経路の開閉の命令, 意図: 旅行者の意図 },
}

impl M不変データ for 旅のコマンド {}
impl Mコマンド for 旅のコマンド {}

/// 領域の出来事。開閉の出来事か旅行者の出来事である。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 旅の出来事 {
    開閉(経路の開閉の出来事),
    旅行者(旅行者の出来事),
}

impl M不変データ for 旅の出来事 {}
impl Mイベント for 旅の出来事 {}

/// 状態の同一性。地点の表記と、現在地の単精度のビットの並びと、閉じている経路と出来事が触れた経路の表記を丸めずに並べる。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct 旅の状態の同一性(pub String);

/// 村・峠・城下町・港と、峠道・関所・山道の地図。
pub fn 城下町の地図を組む() -> 地点と経路のグラフ {
    let 開いている = || 経路の開閉の予定::時間帯を持たない(経路の開閉::開いている);
    #[rustfmt::skip]
    let つながり = graphite::graph!(地点と経路の図式 {
        村 = 地点::区域で生成する(正方形の区域(0.0, 0.0)),
        峠 = 地点::区域で生成する(正方形の区域(区域の一辺, 0.0)),
        城下町 = 地点::区域で生成する(正方形の区域(区域の一辺, 区域の一辺)),
        港 = 地点::区域で生成する(正方形の区域(0.0, 区域の一辺)),
        峠道 = 経路(村 -[経路の積み荷::生成する(経路の種類::幹線道路, 通り口(東の真ん中の辺, 西の真ん中の辺), 開いている())]- 峠),
        関所 = 経路(峠 -[経路の積み荷::生成する(経路の種類::門, 通り口(北の真ん中の辺, 南の真ん中の辺), 経路の開閉の予定::時間帯を持たない(経路の開閉::閉じている))]- 城下町),
        山道 = 経路(村 -[経路の積み荷::予定を持たずに生成する(経路の種類::山道, 通り口(北の真ん中の辺, 南の真ん中の辺))]- 港),
    })
    .expect("多重度の制約を持たない図式の地図は組めるべきである");
    地点と経路のグラフ::検証して生成する(つながり.into_graph()).expect("区域と通り口の不変条件を満たす地図は検証を通るべきである")
}

/// 状態の表記。地点・現在地のビットの並び・閉じている経路・出来事が触れた経路を丸めずに並べるため、互いに等しくない2つの状態は別の表記になる。
pub fn 旅の状態の表記(状態: &旅の状態) -> String {
    let 現在地 = 状態.居場所.現在地();
    let 並べる = |一覧: Vec<&str>| 一覧.join("・");
    format!(
        "旅の状態(地点: {} / 東{} / 北{} / 閉じている経路: {} / 出来事が触れた経路: {})",
        状態.居場所.地点().表記(),
        単精度のビットの並び::値から写す(現在地.東().値()).表記(),
        単精度のビットの並び::値から写す(現在地.北().値()).表記(),
        並べる(状態.開閉.閉じている経路一覧().map(|経路| 経路.表記()).collect()),
        並べる(状態.開閉.出来事が触れた経路一覧().map(|経路| 経路.表記()).collect()),
    )
}
