//! 旅の1刻みを数え上げる領域(`旅の数え上げ.rs`)が使う、状態・コマンド・出来事の型と地図と状態の表記(Issue #187 の作業G2)。
//! 領域の型から分けるのは、領域が持つのが有限に数え上げられる領域の契約の実装であり、こちらが持つのがその契約へ渡す値の形と試験の地図だからである。
//!
//! 地図は一辺10メートルの正方形の区域4つ(村・峠・城下町・港)と経路3本を持つ。峠道(村と峠。幹線道路。はじめは開いている)・関所(峠と城下町。門。はじめから閉じている)・
//! 山道(村と港。山道。封鎖できない)である。城下町の区域へ通じる通り口は関所だけであり、港と城下町の境目は閉じた境目である。

