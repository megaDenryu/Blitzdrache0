//! 旅行者の現在地・意図・出来事を設計概念への参照へ写す名指しの工程(Issue #174。PR #177 のBlocker Bで丸めをやめた)。
//!
//! 名前の表記をこの1箇所へ閉じるのは、遷移モデルを組む工程と命題を組む工程が同じ概念を別の表記で書くと、
//! 含意の前件が1文字の違いで偽になり、検証が黙って空虚に成立するためである。
//!
//! **名指しは丸めない。** 位置をマスの番号へ、歩く向きを小数3桁へ丸めていたため、異なる状態と異なるコマンドが
//! 同じ名前へ写り、探索が別物として残した状態を命題の層が同じ1件として引き当てられた。
//! 現在地の名前は状態の同一性(`現在地のビット表現`)から導き、歩く向きの名前も単精度のビットの並びから導く。
//! これにより名指しの単射性は、書き手の注意ではなく写しの形が保つ。人が読む粗い表記は `behavior_display` が別に持つ。

use blitz_design_verification::設計概念への参照;

use super::behavior_bits::単精度のビットの並び;
use super::behavior_identity::現在地のビット表現;
use crate::traveler::{旅行者の出来事, 旅行者の意図, 旅行者の現在地};
use crate::walking_direction::歩行方向;

// 名指しが使う名前の空間。旅行者の型が居るモジュールを表す。
const 旅行者の名前の空間: &str = "blitz_esca::traveler";

/// 旅行者の現在地を名指す。名前を状態の同一性から導くため、異なる現在地が同じ参照へ写ることは無い。
pub fn 旅行者の現在地を名指す(現在地: &旅行者の現在地) -> 設計概念への参照 {
    let 表記 = format!("旅行者の現在地({})", 現在地のビット表現::現在地から写す(現在地).表記());
    設計概念への参照::実行時のドメイン概念として生成する(旅行者の名前の空間, &表記)
}

/// 旅行者の意図を名指す。歩く意図は向きまで名前に入れ、選択肢と向きの両方が名前から読めるようにする。
pub fn 旅行者の意図を名指す(意図: &旅行者の意図) -> 設計概念への参照 {
    let 表記 = match 意図 {
        旅行者の意図::静止 => "旅行者の意図(静止)".to_string(),
        旅行者の意図::見回す => "旅行者の意図(見回す)".to_string(),
        旅行者の意図::歩く { 方向 } => format!("旅行者の意図(歩く: {})", 歩く向きの表記(方向)),
    };
    設計概念への参照::実行時のドメイン概念として生成する(旅行者の名前の空間, &表記)
}

/// 歩行遷移の規則を名指す。遷移1件がどの規則の下で起きたかを遷移モデルの記録へ残すために要る。
pub fn 歩行遷移の規則を名指す() -> 設計概念への参照 {
    設計概念への参照::実行時のドメイン概念として生成する("blitz_esca::traveler_movement", "歩行遷移の規則")
}

/// 旅行者の出来事を名指す。選択肢が2つあり、どちらも別の名前を持つ。
pub fn 旅行者の出来事を名指す(出来事: &旅行者の出来事) -> 設計概念への参照 {
    let 表記 = match 出来事 {
        旅行者の出来事::周囲を観察した => "旅行者の出来事(周囲を観察した)",
        旅行者の出来事::障害物に遮られた => "旅行者の出来事(障害物に遮られた)",
    };
    設計概念への参照::実行時のドメイン概念として生成する(旅行者の名前の空間, 表記)
}

// 歩く向きの表記。方角の語で呼び分けず、東と北の比率をどちらも単精度のビットの並びで書く。
// 方角の語を使わないのは、`歩行方向` の等価が単精度の等価であり、正の零と負の零のようにビットの並びが違って
// 等しい2つの値が在るため、方角の語での場合分けがビットの並びの違う2つの向きへ同じ語を与えうるためである。
fn 歩く向きの表記(方向: &歩行方向) -> String {
    let 東 = 単精度のビットの並び::値から写す(方向.東の比率());
    let 北 = 単精度のビットの並び::値から写す(方向.北の比率());
    format!("東の比率{}・北の比率{}", 東.表記(), 北.表記())
}
