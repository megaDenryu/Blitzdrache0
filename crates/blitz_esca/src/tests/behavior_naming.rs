//! 旅行者の現在地・意図・出来事を設計概念の識別子へ写す名指しの工程(Issue #174)。
//!
//! 名前の表記をこの1箇所へ閉じるのは、遷移モデルを組む工程と命題を組む工程が同じ概念を別の表記で書くと、
//! 含意の前件が1文字の違いで偽になり、検証が黙って空虚に成立するためである。
//! 位置をマスの番号へ落とすのは、単精度の表示の桁で同じ位置の名前が揺れないためである。

use blitz_design_verification::設計概念の識別子;
use blitz_math::メートル;

use crate::traveler::{旅行者の出来事, 旅行者の意図, 旅行者の現在地};
use crate::walking_direction::歩行方向;

// 名指しが使う名前の空間。旅行者の型が居るモジュールを表す。
const 旅行者の名前の空間: &str = "blitz_esca::traveler";

/// 現在地を名指すときに使うマスの一辺。位置をこの一辺で割った番号が名前に入り、同じマスに載る位置が同じ識別子になる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 現在地を名指すマスの一辺(メートル);

impl 現在地を名指すマスの一辺 {
    /// 一辺が1メートルのマス。歩行の標準の速さ3メートル毎秒と1秒の経過時間の積がこの一辺の整数倍になる。
    pub fn 一メートル() -> Self {
        Self(メートル::生成する(1.0))
    }

    /// 現在地をマスの番号で名指す。遷移モデルの状態がこの名前で同一視され、探索が有限に収まる。
    pub fn 現在地を名指す(&self, 現在地: &旅行者の現在地) -> 設計概念の識別子 {
        設計概念の識別子::生成する(旅行者の名前の空間, &format!("旅行者の現在地(東{}マス, 北{}マス)", self.マスの番号(現在地.東()), self.マスの番号(現在地.北())))
    }

    // 位置を一辺で割って最も近い整数へ丸めた番号の表記。整数の型へ変換せず表記のうえで丸めるのは、数値の `as` キャストを規約が禁じるためである。
    fn マスの番号(&self, 位置: メートル) -> String {
        format!("{:.0}", (位置.値() / self.0.値()).round())
    }
}

/// 旅行者の意図を名指す。歩く意図は向きまで名前に入れ、選択肢と向きの両方が名前から読めるようにする。
pub fn 旅行者の意図を名指す(意図: &旅行者の意図) -> 設計概念の識別子 {
    let 表記 = match 意図 {
        旅行者の意図::静止 => "旅行者の意図(静止)".to_string(),
        旅行者の意図::見回す => "旅行者の意図(見回す)".to_string(),
        旅行者の意図::歩く { 方向 } => format!("旅行者の意図(歩く: {}へ)", 歩く向きの表記(方向)),
    };
    設計概念の識別子::生成する(旅行者の名前の空間, &表記)
}

/// 歩行遷移の規則を名指す。遷移1件がどの規則の下で起きたかを遷移モデルの記録へ残すために要る。
pub fn 歩行遷移の規則を名指す() -> 設計概念の識別子 {
    設計概念の識別子::生成する("blitz_esca::traveler_movement", "歩行遷移の規則")
}

/// 旅行者の出来事を名指す。
pub fn 旅行者の出来事を名指す(出来事: &旅行者の出来事) -> 設計概念の識別子 {
    let 表記 = match 出来事 {
        旅行者の出来事::周囲を観察した => "旅行者の出来事(周囲を観察した)",
        旅行者の出来事::障害物に遮られた => "旅行者の出来事(障害物に遮られた)",
    };
    設計概念の識別子::生成する(旅行者の名前の空間, 表記)
}

// 歩く向きの表記。標本の4方向は方角の語で名指し、それ以外の向きは比率そのままで名指す。
// 名指せなかった向きを1つの名前へ潰さないのは、解析できなかった入力を黙って対象から外さないという検査の規律による。
fn 歩く向きの表記(方向: &歩行方向) -> String {
    if *方向 == 歩行方向::東() {
        return "東".to_string();
    }
    if *方向 == 歩行方向::西() {
        return "西".to_string();
    }
    if *方向 == 歩行方向::北() {
        return "北".to_string();
    }
    if *方向 == 歩行方向::南() {
        return "南".to_string();
    }
    format!("東の比率{:.3}・北の比率{:.3}", 方向.東の比率(), 方向.北の比率())
}
