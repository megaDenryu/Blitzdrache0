//! 点が単純多角形の内側・境界の上・外側のどれにあるかを答える工程。
//! 切り出しの根拠は、呼び出し連鎖の中の独立した工程である(CLAUDE.md「切り出しの根拠義務」の5号)。受け取るのは点、返すのは多角形に対する位置である。
//! 境界の上かを先に境界の許容幅で判断するのは、単精度へ戻した点が境界からわずかに外れても、境界の上として扱うためである。

use super::多角形::単純多角形;
use super::点と線分::平面の点;

/// 点が多角形に対してどこにあるか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 多角形に対する位置 {
    内側,
    境界の上,
    外側,
}

impl 単純多角形 {
    /// 点がこの多角形の内側・境界の上・外側のどれにあるか。境界の上かは境界の許容幅で判断し、内側か外側かは北の向きに一定な直線と辺の交わりの数で判断する。
    pub fn 点の位置(&self, 点: &平面の点) -> 多角形に対する位置 {
        if self.辺一覧().any(|辺| 辺.点までの距離(点) <= 点.境界の許容幅()) {
            return 多角形に対する位置::境界の上;
        }
        let 東 = 点.東.値();
        let 北 = 点.北.値();
        let 交わりの数 = self
            .辺一覧()
            .filter(|辺| {
                let (始まりの北, 終わりの北) = (辺.始点.北.値(), 辺.終点.北.値());
                if (始まりの北 > 北) == (終わりの北 > 北) {
                    return false;
                }
                let 交わる東 = 辺.始点.東.値() + (北 - 始まりの北) * (辺.終点.東.値() - 辺.始点.東.値()) / (終わりの北 - 始まりの北);
                東 < 交わる東
            })
            .count();
        if 交わりの数 % 2 == 1 { 多角形に対する位置::内側 } else { 多角形に対する位置::外側 }
    }

    /// 点がこの多角形の内側か境界の上にあるか。
    pub fn 閉包に入るか(&self, 点: &平面の点) -> bool {
        self.点の位置(点) != 多角形に対する位置::外側
    }
}
