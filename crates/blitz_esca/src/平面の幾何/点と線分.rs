//! 地面を上から見た平面の点と線分。東と北の2成分を倍精度のメートル(`大域メートル`)で持つ。
//! 倍精度で持つのは、区域の頂点と旅行者の現在地がどちらも単精度であり、その差と外積を倍精度で計算すると丸めがほとんど起きないためである。
//! 計算の内側では単位を外した2成分のベクトル(`平面のベクトル`)を使う。単位を外すのはこのモジュールの中だけである。

use blitz_math::大域メートル;

/// 地面を上から見た平面の点。東と北をメートルで持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 平面の点 {
    pub 東: 大域メートル,
    pub 北: 大域メートル,
}

/// 始点から終点へ張る平面の線分。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 平面の線分 {
    pub 始点: 平面の点,
    pub 終点: 平面の点,
}

/// 幾何の計算の内側で使う、単位を外した2成分のベクトル。成分の単位はメートルである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 平面のベクトル {
    東: f64,
    北: f64,
}

impl 平面のベクトル {
    pub(crate) fn 外積(self, 相手: Self) -> f64 {
        self.東 * 相手.北 - self.北 * 相手.東
    }

    pub(crate) fn 内積(self, 相手: Self) -> f64 {
        self.東 * 相手.東 + self.北 * 相手.北
    }

    pub(crate) fn 足す(self, 相手: Self) -> Self {
        Self {
            東: self.東 + 相手.東, 北: self.北 + 相手.北
        }
    }

    pub(crate) fn 倍する(self, 倍率: f64) -> Self {
        Self {
            東: self.東 * 倍率, 北: self.北 * 倍率
        }
    }
}

impl 平面の点 {
    pub(crate) fn 原点からのベクトル(&self) -> 平面のベクトル {
        平面のベクトル { 東: self.東.値(), 北: self.北.値() }
    }

    pub(crate) fn 原点からのベクトルから作る(ベクトル: 平面のベクトル) -> Self {
        Self {
            東: 大域メートル::生成する(ベクトル.東),
            北: 大域メートル::生成する(ベクトル.北),
        }
    }

    /// この点から相手の点へ向かうベクトル。
    pub(crate) fn 相手へのベクトル(&self, 相手: &Self) -> 平面のベクトル {
        平面のベクトル {
            東: 相手.東.値() - self.東.値(),
            北: 相手.北.値() - self.北.値(),
        }
    }

    /// 2つの成分がどちらも有限な数値か。
    pub fn 有限か(&self) -> bool {
        self.東.値().is_finite() && self.北.値().is_finite()
    }

    /// この点で境界の上とみなす距離の幅。単精度の座標を倍精度へ広げて計算した点は、単精度へ戻すと座標の大きさの2の24乗分の1ほど動くため、
    /// その16倍(座標の大きさの2の20乗分の1)を幅にする。座標が1メートルより小さいところでは1メートルの座標と同じ幅にする。
    pub(crate) fn 境界の許容幅(&self) -> f64 {
        let 大きさ = self.東.値().abs().max(self.北.値().abs()).max(1.0);
        大きさ * 境界の許容幅の比
    }
}

// 境界の上とみなす幅の、座標の大きさに対する比(2の20乗分の1)。
const 境界の許容幅の比: f64 = 1.0 / 1_048_576.0;

impl 平面の線分 {
    /// 始点から終点へのベクトル。
    pub(crate) fn 向き(&self) -> 平面のベクトル {
        self.始点.相手へのベクトル(&self.終点)
    }

    /// 媒介変数(始点で0、終点で1)の位置の点。
    pub(crate) fn 媒介変数の点(&self, 媒介変数: f64) -> 平面の点 {
        平面の点::原点からのベクトルから作る(self.始点.原点からのベクトル().足す(self.向き().倍する(媒介変数)))
    }

    /// 点からこの線分までの最短の距離。
    pub(crate) fn 点までの距離(&self, 点: &平面の点) -> f64 {
        let 向き = self.向き();
        let 始点から = self.始点.相手へのベクトル(点);
        let 長さの二乗 = 向き.内積(向き);
        let 媒介変数 = if 長さの二乗 == 0.0 { 0.0 } else { (始点から.内積(向き) / 長さの二乗).clamp(0.0, 1.0) };
        let 最近点 = self.媒介変数の点(媒介変数);
        let 差 = 最近点.相手へのベクトル(点);
        差.内積(差).sqrt()
    }
}
