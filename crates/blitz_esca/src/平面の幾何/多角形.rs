//! 単純多角形。自己交差せず、頂点が反時計回りに並ぶ、3つ以上の頂点の多角形である。検証を通らずには作れない。
//! 反時計回りを要求するのは、辺の左側が内側になり、2つの多角形が共有する辺が逆向きに張られることを、通り口と重なりの判定が前提にするためである。
//! 頂点を並べ替えて反時計回りへ直さないのは、辺を始まりの頂点の番号で指す通り口の指定が、並べ替えで別の辺を指してしまうためである。

use super::点と線分::{平面の点, 平面の線分};

/// 自己交差せず、頂点が反時計回りに並ぶ多角形。
#[derive(Debug, Clone, PartialEq)]
pub struct 単純多角形 {
    頂点一覧: Vec<平面の点>,
}

impl 単純多角形 {
    /// 頂点が3つ以上で有限であり、長さ0の辺を持たず、反時計回りに並び、辺どうしが隣の辺と共有する頂点のほかで触れないことを確かめて多角形を作る。
    pub fn 検証する(頂点一覧: Vec<平面の点>) -> Result<Self, 単純多角形の生成の失敗> {
        if 頂点一覧.len() < 3 {
            return Err(単純多角形の生成の失敗::頂点が3つより少ない { 頂点の数: 頂点一覧.len() });
        }
        if let Some(番号) = 頂点一覧.iter().position(|頂点| !頂点.有限か()) {
            return Err(単純多角形の生成の失敗::座標が有限な数値でない { 頂点の番号: 番号 });
        }
        let 多角形 = Self { 頂点一覧 };
        if let Some(番号) = 多角形.辺一覧().position(|辺| 辺.始点 == 辺.終点) {
            return Err(単純多角形の生成の失敗::長さ0の辺がある { 辺の番号: 番号 });
        }
        if 多角形.符号付きの面積の2倍() <= 0.0 {
            return Err(単純多角形の生成の失敗::頂点が反時計回りに並んでいない);
        }
        if let Some(失敗) = 多角形.触れる辺の対を探す() {
            return Err(失敗);
        }
        Ok(多角形)
    }

    pub fn 頂点の数(&self) -> usize {
        self.頂点一覧.len()
    }

    /// 始まりの頂点の番号が指す辺。番号が頂点の数以上なら無しである。
    pub fn 辺(&self, 始まりの頂点の番号: usize) -> Option<平面の線分> {
        let 始点 = *self.頂点一覧.get(始まりの頂点の番号)?;
        let 終点 = self.頂点一覧[(始まりの頂点の番号 + 1) % self.頂点一覧.len()];
        Some(平面の線分 { 始点, 終点 })
    }

    /// 辺を始まりの頂点の番号の順に並べる。
    pub fn 辺一覧(&self) -> impl Iterator<Item = 平面の線分> + '_ {
        (0..self.頂点一覧.len()).filter_map(|番号| self.辺(番号))
    }

    /// 頂点を番号の順に並べる。
    pub fn 頂点一覧(&self) -> &[平面の点] {
        &self.頂点一覧
    }

    // 靴ひもの公式による符号付きの面積の2倍。反時計回りなら正である。
    fn 符号付きの面積の2倍(&self) -> f64 {
        self.辺一覧().map(|辺| 辺.始点.原点からのベクトル().外積(辺.終点.原点からのベクトル())).sum()
    }

    // 触れてはならない辺の対のうち最初の1つを失敗として返す。隣り合わない辺どうしは触れてはならず、隣り合う辺は共有する頂点のほかで触れてはならない。
    fn 触れる辺の対を探す(&self) -> Option<単純多角形の生成の失敗> {
        let 数 = self.頂点一覧.len();
        let 辺一覧: Vec<平面の線分> = self.辺一覧().collect();
        for 一方 in 0..数 {
            for もう一方 in (一方 + 1)..数 {
                let 隣り合う = もう一方 == 一方 + 1 || (一方 == 0 && もう一方 == 数 - 1);
                let 触れる = if 隣り合う {
                    隣の辺と重なるか(&辺一覧[一方], &辺一覧[もう一方])
                } else {
                    !辺一覧[一方].相手に触れる媒介変数一覧(&辺一覧[もう一方]).is_empty()
                };
                if 触れる {
                    return Some(単純多角形の生成の失敗::辺どうしが触れている {
                        一方の辺: 一方, もう一方の辺: もう一方
                    });
                }
            }
        }
        None
    }
}

// 隣り合う2つの辺が、共有する頂点のほかで触れるか。共有しない側の端点が相手の辺に載れば、2つの辺は折り返して重なっている。
fn 隣の辺と重なるか(一方: &平面の線分, もう一方: &平面の線分) -> bool {
    let 共有しない端点 = |辺: &平面の線分, 相手: &平面の線分| if 辺.始点 == 相手.終点 { 辺.終点 } else { 辺.始点 };
    let 一方の端点 = 共有しない端点(一方, もう一方);
    let もう一方の端点 = 共有しない端点(もう一方, 一方);
    もう一方.点までの距離(&一方の端点) <= 一方の端点.境界の許容幅() || 一方.点までの距離(&もう一方の端点) <= もう一方の端点.境界の許容幅()
}

/// 単純多角形の頂点の並びが不変条件を満たさなかった理由。
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum 単純多角形の生成の失敗 {
    #[error("頂点が{頂点の数}つしかない(多角形の頂点は3つ以上でなければならない)")]
    頂点が3つより少ない { 頂点の数: usize },
    #[error("{頂点の番号}番の頂点の座標が有限な数値でない(頂点の座標は有限な数値でなければならない)")]
    座標が有限な数値でない { 頂点の番号: usize },
    #[error("{辺の番号}番の辺の長さが0である(隣り合う頂点は別の位置になければならない)")]
    長さ0の辺がある { 辺の番号: usize },
    #[error("頂点が反時計回りに並んでいない(北を上に見て反時計回りに並べ、面積が0より大きくなければならない)")]
    頂点が反時計回りに並んでいない,
    #[error("{一方の辺}番の辺と{もう一方の辺}番の辺が触れている(多角形は自己交差してはならない)")]
    辺どうしが触れている { 一方の辺: usize, もう一方の辺: usize },
}
