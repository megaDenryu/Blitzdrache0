//! 境界に当たった動きを、当たった辺に沿わせる工程。多角形の外へ出ようとした線分の残りから、辺に垂直な成分を除き、辺に沿う成分だけを残す。
//! 切り出しの根拠は、呼び出し連鎖の中の独立した工程である(CLAUDE.md「切り出しの根拠義務」の5号)。受け取るのは境界の上の点と、行こうとした終点であり、返すのは沿わせた終点である。
//! 境界の上の点が頂点(角)にあるときは沿わせる辺が1つに決まらないため、沿わせず止める。長方形の範囲の角へ斜めに歩いたとき、角で止まるのと同じ振る舞いである。

use super::多角形::単純多角形;
use super::点と線分::平面の点;

impl 単純多角形 {
    /// 境界の上の点から終点へ向かう動きを、その点が載る辺に沿わせた終点。点が頂点にあるか、どの辺にも載っていないか、沿う成分が無ければ無しである。
    pub fn 境界に沿わせた終点(&self, 境界の上の点: &平面の点, 終点: &平面の点) -> Option<平面の点> {
        let 許容幅 = 境界の上の点.境界の許容幅();
        if self.頂点一覧().iter().any(|頂点| {
            let 差 = 頂点.相手へのベクトル(境界の上の点);
            差.内積(差).sqrt() <= 許容幅
        }) {
            return None;
        }
        let 辺 = self.辺一覧().find(|辺| 辺.点までの距離(境界の上の点) <= 許容幅)?;
        let 向き = 辺.向き();
        let 沿う長さの比 = 境界の上の点.相手へのベクトル(終点).内積(向き) / 向き.内積(向き);
        if 沿う長さの比 == 0.0 {
            return None;
        }
        Some(平面の点::原点からのベクトルから作る(境界の上の点.原点からのベクトル().足す(向き.倍する(沿う長さの比))))
    }
}
