//! 2つの単純多角形の内部が重なるかを答える工程。境界だけを共有する2つの多角形(辺を共有して隣り合う区域)は重ならない。
//! 切り出しの根拠は、呼び出し連鎖の中の独立した工程である(CLAUDE.md「切り出しの根拠義務」の5号)。受け取るのは相手の多角形、返すのは真偽である。
//!
//! 内部が重なるのは次の2つのどちらかが起きるときである。片方の境界の一部が、もう片方の内側を通る。または、2つの境界が同じ向きに重なる辺を持つ。
//! 前者は、交わる・含む・頂点が食い込むといった重なりを捕まえる。後者は、2つの多角形がそっくり同じ場合のように境界が全部相手の境界の上にある重なりを捕まえる。
//! 反時計回りの2つの多角形が辺を共有して隣り合うとき、その辺は2つで逆向きに張られるため、後者に当たらない。

use super::多角形::単純多角形;

impl 単純多角形 {
    /// この多角形と相手の多角形の内部が重なるか。
    pub fn 内部が重なるか(&self, 相手: &単純多角形) -> bool {
        let 境界の一部が内側を通る = self.辺一覧().any(|辺| 相手.線分の一部が内側を通るか(&辺)) || 相手.辺一覧().any(|辺| self.線分の一部が内側を通るか(&辺));
        境界の一部が内側を通る || self.辺一覧().any(|辺| 相手.辺一覧().any(|相手の辺| 辺.同じ向きに重なるか(&相手の辺)))
    }
}
