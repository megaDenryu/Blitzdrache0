//! 線分を単純多角形の境界に触れる位置で区切り、区切った区間ごとに多角形のどこを通るかを答える工程。
//! 切り出しの根拠は、呼び出し連鎖の中の独立した工程である(CLAUDE.md「切り出しの根拠義務」の5号)。受け取るのは線分、返すのは媒介変数か真偽である。
//! 区切った区間の中では線分が境界に触れないため、区間の中点1つの位置がその区間全体の位置である。区間の中点で判断するのは、
//! 凹んだ頂点をかすめる線分や、境界に沿って進む線分を、辺の向きだけで判断すると取り違えるためである。

use super::多角形::単純多角形;
use super::点と線分::平面の線分;
use super::点の位置::多角形に対する位置;

impl 単純多角形 {
    /// 線分がこの多角形の閉包(内側と境界の上)から初めて外へ出る位置の媒介変数。外へ出なければ無しである。
    pub fn 線分が初めて外へ出る媒介変数(&self, 線分: &平面の線分) -> Option<f64> {
        self.区間一覧(線分).find(|区間| self.区間の位置(線分, 区間) == 多角形に対する位置::外側).map(|区間| 区間.始まり)
    }

    /// 線分を区切った最初の区間が、この多角形の閉包に入るか。線分の長さが0なら、始点が閉包に入るかである。
    pub fn 線分の始めの区間が閉包に入るか(&self, 線分: &平面の線分) -> bool {
        match self.区間一覧(線分).next() {
            Some(区間) => self.区間の位置(線分, &区間) != 多角形に対する位置::外側,
            None => self.閉包に入るか(&線分.始点),
        }
    }

    /// 線分を区切った区間のどれかが、この多角形の内側(境界の上でなく)を通るか。
    pub(crate) fn 線分の一部が内側を通るか(&self, 線分: &平面の線分) -> bool {
        self.区間一覧(線分).any(|区間| self.区間の位置(線分, &区間) == 多角形に対する位置::内側)
    }

    // 線分を境界に触れる位置で区切った、長さのある区間を始点の側から並べる。
    fn 区間一覧(&self, 線分: &平面の線分) -> impl Iterator<Item = 線分の区間> {
        let mut 区切り一覧: Vec<f64> = self.辺一覧().flat_map(|辺| 線分.相手に触れる媒介変数一覧(&辺)).collect();
        区切り一覧.push(0.0);
        区切り一覧.push(1.0);
        区切り一覧.sort_by(f64::total_cmp);
        区切り一覧.dedup();
        let 区間一覧: Vec<線分の区間> = 区切り一覧.windows(2).filter_map(|対| 線分の区間::端から作る(対)).collect();
        区間一覧.into_iter()
    }

    fn 区間の位置(&self, 線分: &平面の線分, 区間: &線分の区間) -> 多角形に対する位置 {
        self.点の位置(&線分.媒介変数の点((区間.始まり + 区間.終わり) / 2.0))
    }
}

// 線分を区切った1つの区間。始まりと終わりは線分の媒介変数であり、始まりは終わりより小さい。
struct 線分の区間 {
    始まり: f64,
    終わり: f64,
}

impl 線分の区間 {
    // 隣り合う2つの区切りから区間を作る。長さの無い区間は作らない。
    fn 端から作る(対: &[f64]) -> Option<Self> {
        match 対 {
            [始まり, 終わり] if 終わり > 始まり => Some(Self { 始まり: *始まり, 終わり: *終わり }),
            _ => None,
        }
    }
}
