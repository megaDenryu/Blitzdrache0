//! 2つの線分が触れる位置を、片方の線分の媒介変数(始点で0、終点で1)で答える工程。
//! 切り出しの根拠は、呼び出し連鎖の中の独立した工程である(CLAUDE.md「切り出しの根拠義務」の5号)。受け取るのは2つの線分、返すのは媒介変数の一覧である。
//! 多角形が線分を境界で区切る工程(`線分の区切り.rs`)と、2つの多角形の内部が重なるかの判定(`多角形の重なり.rs`)がこれを使う。

use super::点と線分::{平面の点, 平面の線分};

impl 平面の線分 {
    /// この線分が相手の線分に触れる、この線分の媒介変数の一覧。どれも0以上1以下である。
    /// 2つの線分が1点で交わる位置と、相手の端点がこの線分に載る位置を返す。同じ直線の上で重なる区間は、相手の端点が載る位置としてその両端が返る。
    /// 載っているかは境界の許容幅で判断し、丸めで端点がわずかに外れた触れ方を落とさない。
    pub(crate) fn 相手に触れる媒介変数一覧(&self, 相手: &平面の線分) -> Vec<f64> {
        let 向き = self.向き();
        let 長さの二乗 = 向き.内積(向き);
        if 長さの二乗 == 0.0 {
            return Vec::new();
        }
        let mut 一覧: Vec<f64> = [相手.始点, 相手.終点].iter().filter_map(|端点| self.載る点の媒介変数(端点)).collect();
        if let Some(媒介変数) = self.交わる点の媒介変数(相手) {
            一覧.push(媒介変数);
        }
        一覧
    }

    // 点がこの線分に載っていれば、その点をこの線分へ正射影した位置の媒介変数。
    fn 載る点の媒介変数(&self, 点: &平面の点) -> Option<f64> {
        if self.点までの距離(点) > 点.境界の許容幅() {
            return None;
        }
        let 向き = self.向き();
        Some((self.始点.相手へのベクトル(点).内積(向き) / 向き.内積(向き)).clamp(0.0, 1.0))
    }

    // 2つの線分が平行でなく1点で交わるとき、その点のこの線分の媒介変数。
    fn 交わる点の媒介変数(&self, 相手: &平面の線分) -> Option<f64> {
        let 向き = self.向き();
        let 相手の向き = 相手.向き();
        let 分母 = 向き.外積(相手の向き);
        if 分母 == 0.0 {
            return None;
        }
        let 始点どうし = self.始点.相手へのベクトル(&相手.始点);
        let 媒介変数 = 始点どうし.外積(相手の向き) / 分母;
        let 相手の媒介変数 = 始点どうし.外積(向き) / 分母;
        let 範囲 = 0.0..=1.0;
        (範囲.contains(&媒介変数) && 範囲.contains(&相手の媒介変数)).then_some(媒介変数)
    }

    /// 2つの線分が同じ直線の上にあり、同じ向きに、境界の許容幅より長い区間で重なるか。端点を1つ共有するだけの並びは重なりに数えない。
    /// 反時計回りの2つの区域が辺を共有するとき、その辺は2つの区域で逆向きに張られる。同じ向きに重なる辺は、2つの区域の内部がその辺の同じ側にあることを表す。
    pub(crate) fn 同じ向きに重なるか(&self, 相手: &平面の線分) -> bool {
        let 向き = self.向き();
        let 長さの二乗 = 向き.内積(向き);
        if 長さの二乗 == 0.0 || 向き.内積(相手.向き()) <= 0.0 {
            return false;
        }
        let 同じ直線の上か = [相手.始点, 相手.終点].iter().all(|端点| self.始点.相手へのベクトル(端点).外積(向き).abs() / 長さの二乗.sqrt() <= 端点.境界の許容幅());
        if !同じ直線の上か {
            return false;
        }
        let 射影 = |端点: &平面の点| self.始点.相手へのベクトル(端点).内積(向き) / 長さの二乗;
        let 重なりの始まり = 射影(&相手.始点).max(0.0);
        let 重なりの終わり = 射影(&相手.終点).min(1.0);
        (重なりの終わり - 重なりの始まり) * 長さの二乗.sqrt() > self.始点.境界の許容幅().max(self.終点.境界の許容幅())
    }
}
