//! 旅行者のキーボード入力解釈テスト(Issue #137)。

#[cfg(test)]
mod tests {
    use crate::traveler::旅行者の意図;
    use crate::traveler_input::{キーボード歩行入力, 歩行入力を解釈する};

    #[test]
    fn 入力解釈_何も押していない時は静止になる() {
        let 入力 = キーボード歩行入力::default();
        let 意図 = 歩行入力を解釈する(&入力);
        assert_eq!(意図, 旅行者の意図::静止);
    }

    #[test]
    fn 入力解釈_単一方向キーで該当方角へ歩く意図になる() {
        let 入力_上 = キーボード歩行入力 { 上: true, ..Default::default() };
        assert_eq!(
            歩行入力を解釈する(&入力_上),
            旅行者の意図::歩く { 東の比率: 0.0, 北の比率: 1.0 }
        );

        let 入力_右 = キーボード歩行入力 { 右: true, ..Default::default() };
        assert_eq!(
            歩行入力を解釈する(&入力_右),
            旅行者の意図::歩く { 東の比率: 1.0, 北の比率: 0.0 }
        );
    }

    #[test]
    fn 入力解釈_斜め入力時は長さが正規化される() {
        let 入力 = キーボード歩行入力 { 上: true, 右: true, ..Default::default() };
        let 意図 = 歩行入力を解釈する(&入力);
        let 期待値 = 1.0_f32 / 2.0_f32.sqrt();
        match 意図 {
            旅行者の意図::歩く { 東の比率, 北の比率 } => {
                assert!((東の比率 - 期待値).abs() < 1e-6);
                assert!((北の比率 - 期待値).abs() < 1e-6);
            }
            _ => panic!("歩く意図になるべきです"),
        }
    }

    #[test]
    fn 入力解釈_相反するキー同時押しは相殺されて静止になる() {
        let 入力 = キーボード歩行入力 {
            上: true,
            下: true,
            左: true,
            右: true,
        };
        assert_eq!(歩行入力を解釈する(&入力), 旅行者の意図::静止);
    }
}
