//! ゲーム『Esca』の第2段階「地点と経路の表現」。地点と経路のつながりと経路の開閉(Issue #187 の作業G1)と、区域と歩行との接続(作業G2)を持つ。
//!
//! つながりは、ステージを作る時点で通れる可能性のある経路を全部置いた、作った後に変わらない地図(`地点と経路のグラフ`)として持つ。
//! 地点は地面を上から見た多角形の区域を持ち、経路は種類と、両端の区域が共有する辺で指す通り口と、開閉の予定を持つ。地図は区域と通り口の不変条件を検証してから作る。
//! どの経路がいま閉じているかは、地図と別の状態(`経路の開閉の状態`)として持ち、開閉の遷移がその新しい値を返す。状態は地図を持つ規則(`経路の開閉の規則`)からだけ作る。
//! 開閉のきっかけは、出来事から作られる開閉の命令と、遷移パラメータの時刻に来た予定の2つである。閉じられるのは封鎖できる種類の経路だけである。
//! 歩行の側は、開閉の状態から導いた通れる通り口と地図の区域を空間制約(`区域の空間制約`)として受け取り、区域の境目では滑り、開いた通り口では隣の区域へ入る。
//! 参照: `_doc/設計/Esca/設計正本.md` 5節。

