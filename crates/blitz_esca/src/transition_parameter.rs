//! 遷移関数の実行に必要な引数を1つのオブジェクトへ束ねた遷移パラメータ(`MParameter`)。
//! 状態でもコマンドでも規則でもない、遷移を成立させる必須の入力(経過時間と、この刻みが始まった世界の時刻)を、生の値の並びでなく名前付きのプロパティで渡すために置く。
//! 1回の遷移は、刻みの始まりの時刻から経過時間だけ進む時間の区間を覆う。経路の開閉の遷移は、その区間に来た時刻の予定だけを当てる。
//! 刻みの終わりは次の刻みの始まりであり、この型の `次の刻みへ進める` だけがそれを作る。区間の判定と次の始まりが同じ1つの足し算を読むため、隣り合う刻みの区間に隙間も重なりもできない。
//! フィールドを私有にし、作る口を `最初の刻みを生成する` と `次の刻みへ進める` の2つに限るのは、構造体リテラルで任意の始まりの時刻を持つ刻みを作り、前の刻みとの間に隙間や重なりを作れないようにするためである。
//! `MParameter` の法則により `Option<T>` のフィールドを持たない(`cargo xtask conform` が検査する)。参照: `_doc/設計/設計オントロジー.md` 2.6節・3.5.1。

use blitz_design::{MParameter, M不変データ};
use blitz_math::大域秒;

use crate::elapsed_time::経過時間;
use crate::時刻::{世界の時刻, 世界の時刻の生成の失敗};

/// 遷移関数へ渡す必須入力の束。この刻みが進める経過時間と、この刻みが始まった世界の時刻を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 遷移パラメータ {
    経過時間: 経過時間,
    刻みの始まりの時刻: 世界の時刻,
}

impl M不変データ for 遷移パラメータ {}
impl MParameter for 遷移パラメータ {}

impl 遷移パラメータ {
    /// 世界の始まりの時刻から始まり、与えた経過時間だけ進む最初の刻み。2つ目からの刻みは `次の刻みへ進める` で作る。
    pub fn 最初の刻みを生成する(世界の始まりの時刻: 世界の時刻, 経過時間: 経過時間) -> Self {
        Self {
            経過時間,
            刻みの始まりの時刻: 世界の始まりの時刻,
        }
    }

    /// この刻みが進める経過時間。
    pub fn 経過時間(&self) -> 経過時間 {
        self.経過時間
    }

    /// この刻みが始まった世界の時刻。
    pub fn 刻みの始まりの時刻(&self) -> 世界の時刻 {
        self.刻みの始まりの時刻
    }

    /// その時刻が、この刻みが覆う区間(始まりの時刻を含み、経過時間だけ進んだ時点を含まない)に来るか。
    /// 区間の終わりを含めないのは、隣り合う2つの刻みが同じ時刻を2回数えないためである。経過時間が0の刻みはどの時刻も覆わない。
    pub fn その時刻がこの刻みに来るか(&self, 時刻: 世界の時刻) -> bool {
        self.刻みの始まりの時刻 <= 時刻 && 時刻.大域秒() < self.刻みの終わりの大域秒()
    }

    /// この刻みの終わりを始まりとし、与えた経過時間だけ進む次の刻み。終わりが倍精度の表現範囲を超えるなら世界の時刻にならず失敗する。
    pub fn 次の刻みへ進める(&self, 次の経過時間: 経過時間) -> Result<Self, 世界の時刻の生成の失敗> {
        Ok(Self {
            経過時間: 次の経過時間,
            刻みの始まりの時刻: 世界の時刻::生成する(self.刻みの終わりの大域秒())?,
        })
    }

    // 刻みの終わり(次の刻みの始まり)。区間の判定と次の刻みの始まりの両方がこの1つを読む。
    fn 刻みの終わりの大域秒(&self) -> 大域秒 {
        self.刻みの始まりの時刻.経過時間だけ進んだ大域秒(self.経過時間)
    }
}
