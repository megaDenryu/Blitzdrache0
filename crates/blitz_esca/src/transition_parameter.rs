//! 遷移関数の実行に必要な引数を1つのオブジェクトへ束ねた遷移パラメータ(`MParameter`)。
//! 状態でもコマンドでも規則でもない、遷移を成立させる必須の入力(経過時間と、この刻みが始まった世界の時刻)を、生の値の並びでなく名前付きのプロパティで渡すために置く。
//! 1回の遷移は、刻みの始まりの時刻から経過時間だけ進む時間の区間を覆う。経路の開閉の遷移は、その区間に来た時刻の予定だけを当てる。
//! `MParameter` の法則により `Option<T>` のフィールドを持たない(`cargo xtask conform` が検査する)。参照: `_doc/設計/設計オントロジー.md` 2.6節・3.5.1。

use blitz_design::{MParameter, M不変データ};

use crate::elapsed_time::経過時間;
use crate::時刻::世界の時刻;

/// 遷移関数へ渡す必須入力の束。この刻みが進める経過時間と、この刻みが始まった世界の時刻を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 遷移パラメータ {
    pub 経過時間: 経過時間,
    pub 刻みの始まりの時刻: 世界の時刻,
}

impl M不変データ for 遷移パラメータ {}
impl MParameter for 遷移パラメータ {}

impl 遷移パラメータ {
    /// その時刻が、この刻みが覆う区間(始まりの時刻を含み、経過時間だけ進んだ時点を含まない)に来るか。
    /// 区間の終わりを含めないのは、隣り合う2つの刻みが同じ時刻を2回数えないためである。経過時間が0の刻みはどの時刻も覆わない。
    pub fn その時刻がこの刻みに来るか(&self, 時刻: 世界の時刻) -> bool {
        self.刻みの始まりの時刻 <= 時刻 && 時刻.秒() < self.刻みの始まりの時刻.経過時間だけ進んだ秒(self.経過時間)
    }
}
