//! 旅行者の歩行の規則と描画位置(判断: Esca設計正本)。
//!
//! 歩行の遷移そのもの(M遷移関数)と描画位置の射影(M射影関数)は、状態の型と同じファイル(`居場所.rs`)に置く。
//! ここは遷移へ読み取り専用で与える規則と、射影が返す描画用のDTOを持つ。
//! 規則は身体の運動法則(`歩行の規則`)と空間制約(`区域の空間制約`。地図の区域と、いま通れる通り口)を直交させて合成する(設計正本 4.4 条2)。
//! 通れる通り口は別の仕組み(経路の開閉)の状態から刻みごとに導いた読み取り専用の値であり、規則の一部として渡してよい(設計オントロジー 3.5.2。2026-09-26 オーナー裁定)。

use blitz_design::{M不変データ, M規則};
use blitz_math::メートル;

use crate::traveler::歩行の規則;
use crate::地点と経路::指定の失敗::経路の指定の失敗;
use crate::地点と経路::空間制約::区域の空間制約;
use crate::地点と経路::開閉の状態::経路の開閉の状態;

/// 歩行状態遷移を律する身体規則と空間制約の統合規則(M規則)。
#[derive(Clone)]
pub struct 歩行遷移の規則 {
    身体: 歩行の規則,
    空間制約: 区域の空間制約,
}

impl M不変データ for 歩行遷移の規則 {}
impl M規則 for 歩行遷移の規則 {}

impl 歩行遷移の規則 {
    pub fn 生成する(身体: 歩行の規則, 空間制約: 区域の空間制約) -> Self {
        Self { 身体, 空間制約 }
    }

    /// 同じ身体と地図のまま、新しい経路の開閉の状態から通れる通り口を導き直した規則。開閉が変わった刻みにだけ呼ぶ(地図を複製しない)。
    /// 状態の経路が空間制約の地図に無ければ失敗する。
    pub fn 通れる通り口を導き直す(self, 開閉の状態: &経路の開閉の状態) -> Result<Self, 経路の指定の失敗> {
        Ok(Self {
            身体: self.身体,
            空間制約: self.空間制約.開閉の状態から導き直す(開閉の状態)?,
        })
    }

    pub fn 身体(&self) -> &歩行の規則 {
        &self.身体
    }

    pub fn 空間制約(&self) -> &区域の空間制約 {
        &self.空間制約
    }
}

/// 描画エンジンに渡すための純粋な位置DTO。単位はGPU境界まで保つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 旅行者の描画位置 {
    pub 東メートル: メートル,
    pub 北メートル: メートル,
}

impl M不変データ for 旅行者の描画位置 {}
