//! 旅行者の現在地の遷移の局面(判断: Esca設計正本)。
//!
//! 切り出しの根拠はライフサイクル局面の分離である。`traveler.rs` が現在地の定義(状態そのもの)を持ち、ここは
//! 刻みごとに呼ばれる遷移の工程(M遷移関数: 現在地と意図と規則と経過時間から次の現在地と出来事を導く)と、
//! 描画のたびに呼ばれる一方向の射影(M射影関数: 現在地から描画DTOを取り出す)を `impl 旅行者の現在地` の別ブロックとして持つ。
//! 触れるのは現在地の東と北だけであり、規則と意図は読むだけである。

use blitz_design::{MDTO, M射影関数, M規則, 射影関数として確認する};
use blitz_math::メートル;

use crate::elapsed_time::経過時間;
use crate::ontology::{M遷移関数, 遷移結果, 遷移関数として確認する};
use crate::traveler::{旅行者の出来事, 旅行者の意図, 旅行者の現在地, 歩行の規則};
use crate::traveler_boundary::移動可能範囲;
use crate::walking_direction::歩行方向;

/// 歩行状態遷移を律する身体規則と空間制約の統合規則(M規則)。空間制約が無いことを `None` で表し、無制限を表す番兵の値を持たない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 歩行遷移の規則 {
    pub 身体: 歩行の規則,
    pub 空間制約: Option<移動可能範囲>,
}

impl M規則 for 歩行遷移の規則 {}

impl 歩行遷移の規則 {
    pub fn 制約なし(身体: 歩行の規則) -> Self {
        Self { 身体, 空間制約: None }
    }

    pub fn 空間制約付き(身体: 歩行の規則, 空間制約: 移動可能範囲) -> Self {
        Self { 身体, 空間制約: Some(空間制約) }
    }
}

impl 旅行者の現在地 {
    /// 意図と規則と経過時間から次の現在地と出来事を導く純粋計算(M遷移関数の型シグネチャを満たす)。
    pub fn 歩行を遷移する(&self, 意図: &旅行者の意図, 規則: &歩行遷移の規則, 経過時間: 経過時間) -> 遷移結果<旅行者の現在地, 旅行者の出来事> {
        match 意図 {
            旅行者の意図::静止 => 遷移結果 { 次の状態: *self, 出来事一覧: vec![] },
            旅行者の意図::歩く { 方向 } => self.歩いた結果(方向, 規則, 経過時間),
            旅行者の意図::見回す => 遷移結果 {
                次の状態: *self,
                出来事一覧: vec![旅行者の出来事::周囲を観察した],
            },
        }
    }

    // 歩く意図の遷移。速さと向きと経過時間から目的地を求め、空間制約があればそこへ収める。
    // 出来事は境界に当たったときだけ生じる。現在地しか状態に無いため、歩き始めや立ち止まりの前後の差は判定できず、出来事にしない。
    fn 歩いた結果(&self, 方向: &歩行方向, 規則: &歩行遷移の規則, 経過時間: 経過時間) -> 遷移結果<旅行者の現在地, 旅行者の出来事> {
        let 速さ = 規則.身体.速さ();
        let 目的地 = 旅行者の現在地::生成する(self.東() + 速さ.比で伸ばす(方向.東の比率()) * 経過時間.秒(), self.北() + 速さ.比で伸ばす(方向.北の比率()) * 経過時間.秒());
        let Some(境界) = 規則.空間制約 else {
            return 遷移結果 {
                次の状態: 目的地, 出来事一覧: vec![]
            };
        };
        let 結果 = 境界.制限する(目的地);
        let 出来事一覧 = if 結果.衝突した { vec![旅行者の出来事::障害物に遮られた] } else { vec![] };
        遷移結果 {
            次の状態: 旅行者の現在地::生成する(結果.制限後の東, 結果.制限後の北),
            出来事一覧,
        }
    }

    /// 現在地から描画用DTOを取り出す一方向の射影(M射影関数の型シグネチャを満たす)。
    pub fn 描画位置を射影する(&self) -> 旅行者の描画位置 {
        旅行者の描画位置 {
            東メートル: self.東(), 北メートル: self.北()
        }
    }
}

// 歩行を遷移する の型引数が M状態・Mコマンド・M規則・Mイベント を満たすことをコンパイラに確かめさせる。
const _: M遷移関数<旅行者の現在地, 旅行者の意図, 歩行遷移の規則, 旅行者の出来事> = 遷移関数として確認する(旅行者の現在地::歩行を遷移する);

/// 描画エンジンに渡すための純粋な位置DTO。単位はGPU境界まで保つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 旅行者の描画位置 {
    pub 東メートル: メートル,
    pub 北メートル: メートル,
}

impl MDTO for 旅行者の描画位置 {}

// 描画位置を射影する の型引数が M状態 と MDTO を満たすことをコンパイラに確かめさせる。
const _: M射影関数<旅行者の現在地, 旅行者の描画位置> = 射影関数として確認する(旅行者の現在地::描画位置を射影する);
