//! 旅行者の歩行移動に関する遷移計算と描画射影(判断: Esca設計正本)。
//!
//! (現在地, 意図, 規則, 時間) から次状態と出来事を導出する純粋計算(M遷移関数)と、
//! 現在地から描画DTOを取り出す一方向射影(M射影関数)を担う。

use blitz_math::メートル;

use crate::ontology::{MDTO, M射影関数, M遷移関数, M規則};
use crate::traveler::{旅行者の出来事, 旅行者の意図, 旅行者の現在地, 歩行の規則};
use crate::traveler_boundary::移動可能範囲;

/// 歩行状態遷移を律する身体規則と空間制約の統合規則(M規則)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 歩行遷移の規則 {
    pub 身体: 歩行の規則,
    pub 空間制約: Option<移動可能範囲>,
}

impl M規則 for 歩行遷移の規則 {}

impl 歩行遷移の規則 {
    pub fn 制約なし(身体: 歩行の規則) -> Self {
        Self { 身体, 空間制約: None }
    }

    pub fn 空間制約付き(身体: 歩行の規則, 空間制約: 移動可能範囲) -> Self {
        Self { 身体, 空間制約: Some(空間制約) }
    }
}

/// 歩行時の状態遷移を導出する純粋関数(M遷移関数の型シグネチャを満たす)。
pub fn 歩行を遷移する(
    現在地: &旅行者の現在地,
    意図: &旅行者の意図,
    規則: &歩行遷移の規則,
    経過秒数: f32,
) -> (旅行者の現在地, Vec<旅行者の出来事>) {
    match 意図 {
        旅行者の意図::静止 => (*現在地, vec![旅行者の出来事::立ち止まった]),
        旅行者の意図::歩く { 東の比率, 北の比率 } => {
            let 速さ = 規則.身体.速さ().値();
            let 東移動 = 東の比率 * 速さ * 経過秒数;
            let 北移動 = 北の比率 * 速さ * 経過秒数;
            let 目的の東 = メートル::生成する(現在地.東().値() + 東移動);
            let 目的の北 = メートル::生成する(現在地.北().値() + 北移動);

            if let Some(境界) = 規則.空間制約 {
                let 結果 = 境界.制限する(目的の東, 目的の北);
                let 出来事 = if 結果.衝突した {
                    vec![旅行者の出来事::障害物に遮られた]
                } else {
                    vec![旅行者の出来事::歩行を開始した]
                };
                (旅行者の現在地::生成する(結果.制限後の東, 結果.制限後の北), 出来事)
            } else {
                (
                    旅行者の現在地::生成する(目的の東, 目的の北),
                    vec![旅行者の出来事::歩行を開始した],
                )
            }
        }
        旅行者の意図::見回す => (*現在地, vec![旅行者の出来事::周囲を観察した]),
    }
}

// 静的型宣言: 歩行を遷移する がオントロジー遷移関数の制約を100%満たすことを保証する
const _: M遷移関数<旅行者の現在地, 旅行者の意図, 歩行遷移の規則, 旅行者の出来事> = 歩行を遷移する;

/// 描画エンジンに渡すための純粋な位置DTO。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 旅行者の描画位置 {
    pub 東メートル: f32,
    pub 北メートル: f32,
}

impl MDTO for 旅行者の描画位置 {}

/// 現在地から描画用DTOを取り出す純粋射影関数(M射影関数の型シグネチャを満たす)。
pub fn 描画位置を射影する(現在地: &旅行者の現在地) -> 旅行者の描画位置 {
    旅行者の描画位置 {
        東メートル: 現在地.東().値(),
        北メートル: 現在地.北().値(),
    }
}

// 静的型宣言: 描画位置を射影する がオントロジー射影関数の制約を100%満たすことを保証する
const _: M射影関数<旅行者の現在地, 旅行者の描画位置> = 描画位置を射影する;
