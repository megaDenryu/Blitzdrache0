//! 旅行者のキーボード入力解釈ロジック(Issue #137)。
//!
//! デバイス境界の生入力(M入力)からゲーム内のコマンド(Mコマンド: 旅行者の意図)を
//! 導出する純粋計算(M解釈関数)を担う。

use crate::ontology::{MDTO, M入力, M解釈関数};
use crate::traveler::旅行者の意図;

/// キーボードの上下左右キー押下状態を表す生シグナルDTO。
///
/// ゲーム意味論を持たず、物理的な押下状態のみを保持する。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct キーボード歩行入力 {
    pub 上: bool,
    pub 下: bool,
    pub 左: bool,
    pub 右: bool,
}

impl MDTO for キーボード歩行入力 {}
impl M入力 for キーボード歩行入力 {}

/// 生のキー押下状態から旅行者の歩行意図を導出する純粋関数。
///
/// 斜め入力時は長さを1.0に正規化し、相反する入力(上下・左右同時押し)は相殺する。
pub fn 歩行入力を解釈する(入力: &キーボード歩行入力) -> 旅行者の意図 {
    let 東 = match (入力.右, 入力.左) {
        (true, false) => 1.0_f32,
        (false, true) => -1.0_f32,
        _ => 0.0_f32,
    };
    let 北 = match (入力.上, 入力.下) {
        (true, false) => 1.0_f32,
        (false, true) => -1.0_f32,
        _ => 0.0_f32,
    };

    if 東 == 0.0 && 北 == 0.0 {
        旅行者の意図::静止
    } else {
        let 長さ = (東 * 東 + 北 * 北).sqrt();
        旅行者の意図::歩く {
            東の比率: 東 / 長さ,
            北の比率: 北 / 長さ,
        }
    }
}

// 静的型宣言: 歩行入力を解釈する がオントロジー解釈関数の制約を満たすことを保証する
const _: M解釈関数<キーボード歩行入力, 旅行者の意図> = 歩行入力を解釈する;
