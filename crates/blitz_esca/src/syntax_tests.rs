//! オントロジーの構文解析テスト(Issue #137)。
//!
//! ソースコードのテキスト構文を直接走査し、設計マーカーが文法規約通りに
//! 実装されているかを機械検証する。

#[allow(clippy::unwrap_used)]
mod tests {
    use crate::ontology::オントロジートレイト;
    use crate::syntax_checker::クレート構文検査;

    const 全ソースコード: &[&str] = &[
        include_str!("traveler.rs"),
        include_str!("traveler_movement.rs"),
    ];

    #[test]
    fn 構文解析_mコマンドとm規則の型定義を検証する() {
        let 検査 = クレート構文検査 { ソース一覧: 全ソースコード };
        for 型名 in 検査.トレイト実装型一覧(オントロジートレイト::Mコマンド) {
            assert!(検査.型種別を満たしているか("enum", 型名), "Mコマンド `{型名}` はenumでなければなりません");
        }
        for 型名 in 検査.トレイト実装型一覧(オントロジートレイト::M規則) {
            assert!(検査.型種別を満たしているか("struct", 型名), "M規則 `{型名}` はstructでなければなりません");
        }
    }

    #[test]
    fn 構文解析_m状態を実装する型はmdtoも実装していること() {
        let 検査 = クレート構文検査 { ソース一覧: 全ソースコード };
        let dto一覧 = 検査.トレイト実装型一覧(オントロジートレイト::MDTO);
        for 型 in 検査.トレイト実装型一覧(オントロジートレイト::M状態) {
            assert!(dto一覧.contains(&型), "M状態 `{型}` は MDTO も実装していなければなりません");
        }
    }

    #[test]
    fn 構文解析_mdtoを実装する型は純粋データ規約を満たすこと() {
        let 検査 = クレート構文検査 { ソース一覧: 全ソースコード };
        for 型名 in 検査.トレイト実装型一覧(オントロジートレイト::MDTO) {
            let 違反 = 検査.dto純粋性違反一覧(型名);
            assert!(違反.is_empty(), "MDTO `{型名}` の純粋性違反: {:?}", 違反);
        }
    }

    #[test]
    fn 構文解析_mイベントを実装する型は純粋データ規約を満たすこと() {
        let 検査 = クレート構文検査 { ソース一覧: 全ソースコード };
        for 型名 in 検査.トレイト実装型一覧(オントロジートレイト::Mイベント) {
            let 違反 = 検査.dto純粋性違反一覧(型名);
            assert!(違反.is_empty(), "Mイベント `{型名}` の純粋性違反: {:?}", 違反);
        }
    }

    #[test]
    fn 構文解析_m入力を実装する型はmdtoも実装していること() {
        let 検査 = クレート構文検査 { ソース一覧: 全ソースコード };
        let dto一覧 = 検査.トレイト実装型一覧(オントロジートレイト::MDTO);
        for 型 in 検査.トレイト実装型一覧(オントロジートレイト::M入力) {
            assert!(dto一覧.contains(&型), "M入力 `{型}` は MDTO も実装していなければなりません");
        }
    }

    #[test]
    fn 構文解析_m遷移関数とm射影関数の型引数がオントロジーを満たすこと() {
        let 検査 = クレート構文検査 { ソース一覧: 全ソースコード };
        let 状態 = 検査.トレイト実装型一覧(オントロジートレイト::M状態);
        let コマンド = 検査.トレイト実装型一覧(オントロジートレイト::Mコマンド);
        let 規則 = 検査.トレイト実装型一覧(オントロジートレイト::M規則);
        let イベント = 検査.トレイト実装型一覧(オントロジートレイト::Mイベント);
        let dto = 検査.トレイト実装型一覧(オントロジートレイト::MDTO);

        let 遷移一覧 = 検査.宣言の型引数一覧("M遷移関数");
        assert!(!遷移一覧.is_empty(), "M遷移関数の静的型宣言が存在しません");
        for 引数 in &遷移一覧 {
            assert_eq!(引数.len(), 4, "M遷移関数は4つの型引数が必要です");
            assert!(状態.contains(&引数[0].as_str()), "状態 `{}` が M状態 未実装", 引数[0]);
            assert!(コマンド.contains(&引数[1].as_str()), "コマンド `{}` が Mコマンド 未実装", 引数[1]);
            assert!(規則.contains(&引数[2].as_str()), "規則 `{}` が M規則 未実装", 引数[2]);
            assert!(イベント.contains(&引数[3].as_str()), "出来事 `{}` が Mイベント 未実装", 引数[3]);
        }

        let 射影一覧 = 検査.宣言の型引数一覧("M射影関数");
        assert!(!射影一覧.is_empty(), "M射影関数の静的型宣言が存在しません");
        for 引数 in &射影一覧 {
            assert_eq!(引数.len(), 2, "M射影関数は2つの型引数が必要です");
            assert!(状態.contains(&引数[0].as_str()), "状態 `{}` が M状態 未実装", 引数[0]);
            assert!(dto.contains(&引数[1].as_str()), "射影DTO `{}` が MDTO 未実装", 引数[1]);
        }
    }

    #[test]
    fn 構文解析_可変自己参照メソッドの不在を検証する() {
        let 検査 = クレート構文検査 { ソース一覧: 全ソースコード };
        assert!(!検査.可変参照メソッドを含むか(), "オントロジー構成要素は &mut self メソッドを持てません");
    }
}
