//! 旅行者の居場所と、その歩行の遷移と描画位置の射影(第2段階の区域と歩行の接続。Issue #187 の作業G2)。
//!
//! 居場所は、旅行者がいる地点と、その地点の区域の中の現在地の組であり、歩行の遷移の状態(`M状態`)である。
//! 地点を現在地と一緒に持つのは、境目の上の点が2つの区域のどちらの閉包にも入り、点だけからはいる地点を決められないためである。
//! 閉じた通り口の上に立った旅行者は、来た側の地点にいるまま、向こうの区域へは閉じた境目として遮られる(点から決めると、閉じた門の上に立つだけで向こう側へ移れてしまう)。
//! 遷移は居場所を値で受け取り、居場所がいる地点の区域の外にあれば失敗し、受け取った居場所をそのまま遷移失敗結果に入れて返す。
//! 歩く意図の遷移は、目的地へ向かう動きを空間制約(地図の区域と、いま通れる通り口)の中で動かし、境目で滑るか通り口を抜けた後の地点と現在地を次の居場所にする。
//! 境目に遮られたときだけ `障害物に遮られた` が生じる。

use blitz_design::{M不変データ, M射影関数, M状態};

use crate::ontology::{M遷移関数, 遷移失敗結果, 遷移成功結果};
use crate::transition_parameter::遷移パラメータ;
use crate::traveler::{旅行者の出来事, 旅行者の意図, 旅行者の現在地, 移動の変位};
use crate::traveler_error::歩行の失敗;
use crate::traveler_movement::{旅行者の描画位置, 歩行遷移の規則};
use crate::walking_direction::歩行方向;
use crate::地点と経路::区域の中の移動の型::区域の中の移動の指定;
use crate::地点と経路::識別子::地点の識別子;

/// 旅行者がいる地点と、その地点の区域の中の現在地。
#[derive(Debug, Clone, PartialEq)]
pub struct 旅行者の居場所 {
    地点: 地点の識別子,
    現在地: 旅行者の現在地,
}

impl M不変データ for 旅行者の居場所 {}
impl M状態 for 旅行者の居場所 {}

impl 旅行者の居場所 {
    /// 地点と現在地から居場所を作る。現在地がその地点の区域の中にあるかは、遷移が空間制約の地図で確かめる(別の地図の地点を渡されても、遷移が失敗として報告する)。
    pub fn 生成する(地点: 地点の識別子, 現在地: 旅行者の現在地) -> Self {
        Self { 地点, 現在地 }
    }

    pub fn 地点(&self) -> &地点の識別子 {
        &self.地点
    }

    pub fn 現在地(&self) -> 旅行者の現在地 {
        self.現在地
    }

    /// 居場所を値で受け取り、意図と規則と遷移パラメータ(経過時間)から次の居場所と出来事を導く純粋計算(M遷移関数の型シグネチャを満たす)。
    pub fn 歩行を遷移する(
        self, 意図: &旅行者の意図, 規則: &歩行遷移の規則, パラメータ: 遷移パラメータ
    ) -> Result<遷移成功結果<旅行者の居場所, 旅行者の出来事>, 遷移失敗結果<旅行者の居場所, 歩行の失敗>> {
        match self.意図の結果(意図, 規則, パラメータ) {
            Ok(成功) => Ok(成功),
            Err(失敗の理由) => Err(遷移失敗結果 { 元の状態: self, 失敗の理由 }),
        }
    }

    // 意図ごとの遷移。静止と見回すも、居場所がいる地点の区域の中にあることを先に確かめる(区域の外にいる旅行者の遷移を成功させない)。
    fn 意図の結果(&self, 意図: &旅行者の意図, 規則: &歩行遷移の規則, パラメータ: 遷移パラメータ) -> Result<遷移成功結果<旅行者の居場所, 旅行者の出来事>, 歩行の失敗> {
        let 始点 = self.現在地.平面の点へ広げる();
        let 終点 = match 意図 {
            旅行者の意図::歩く { 方向 } => self.目的地(方向, 規則, パラメータ)?.平面の点へ広げる(),
            旅行者の意図::静止 | 旅行者の意図::見回す => 始点,
        };
        let 動いた = 規則.空間制約().区域の中で動かす(区域の中の移動の指定 { 地点: self.地点.clone(), 始点, 終点 })?;
        let 次の状態 = Self {
            地点: 動いた.地点,
            現在地: 旅行者の現在地::平面の点から狭める(&動いた.到達点)?,
        };
        let 出来事一覧 = match (意図, 動いた.遮られた) {
            (旅行者の意図::見回す, _) => vec![旅行者の出来事::周囲を観察した],
            (_, true) => vec![旅行者の出来事::障害物に遮られた],
            (_, false) => vec![],
        };
        Ok(遷移成功結果 { 次の状態, 出来事一覧 })
    }

    // 速さと向きと経過時間から求めた、区域を考えない目的地。有限な入力の積和でも単精度は無限大になりうるため、現在地の生成の検証を通す。
    fn 目的地(&self, 方向: &歩行方向, 規則: &歩行遷移の規則, パラメータ: 遷移パラメータ) -> Result<旅行者の現在地, 歩行の失敗> {
        let 速さ = 規則.身体().速さ();
        let 経過時間 = パラメータ.経過時間();
        Ok(self.現在地.平行移動する(移動の変位 {
            東: 速さ.比で伸ばす(方向.東の比率()) * 経過時間.秒(),
            北: 速さ.比で伸ばす(方向.北の比率()) * 経過時間.秒(),
        })?)
    }

    /// 居場所から描画用DTOを取り出す一方向の射影(M射影関数の型シグネチャを満たす)。
    pub fn 描画位置を射影する(&self) -> 旅行者の描画位置 {
        旅行者の描画位置 {
            東メートル: self.現在地.東(),
            北メートル: self.現在地.北(),
        }
    }
}

// 歩行を遷移する が遷移の役割(M状態・Mコマンド・M規則 から M状態・Mイベント、失敗は型付きエラー)を満たすことをコンパイラに確かめさせる。
const _: M遷移関数<旅行者の居場所, 旅行者の意図, 歩行遷移の規則, 旅行者の出来事, 歩行の失敗> = M遷移関数::生成する(旅行者の居場所::歩行を遷移する);

// 描画位置を射影する が射影の役割(M状態 から M不変データ)を満たすことをコンパイラに確かめさせる。
const _: M射影関数<旅行者の居場所, 旅行者の描画位置> = M射影関数::生成する(旅行者の居場所::描画位置を射影する);
