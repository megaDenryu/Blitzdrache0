//! 旅行者の居場所と、その歩行の状態遷移と描画位置の射影(第2段階の区域と歩行の接続。Issue #187 の作業G2)。
//!
//! 居場所は、旅行者がいる地点と、その地点の区域の中の現在地の組であり、歩行の状態遷移の状態(`M状態`)である。
//! 地点を現在地と一緒に持つのは、境目の上の点が2つの区域のどちらの閉包にも入り、点だけからはいる地点を決められないためである。
//! 閉じた通り口の上に立った旅行者は、来た側の地点にいるまま、向こうの区域へは閉じた境目として遮られる(点から決めると、閉じた門の上に立つだけで向こう側へ移れてしまう)。
//! 状態遷移は居場所を値で受け取り、失敗しない。居場所が地図に無い地点にいることと、いる地点の区域の外にあることと、次の現在地の座標が有限な数でなくなることは、
//! ゲームの規則として起きることではなく、壊れた状態を渡したプログラムの誤りでしか起きないため、状態遷移は失敗を返さずに停止する(2026-09-28 オーナー裁定。設計オントロジー 3.5.9)。
//! 歩く意図の状態遷移は、目的地へ向かう動きを空間制約(地図の区域と、いま通れる通り口)の中で動かし、境目で滑るか通り口を抜けた後の地点と現在地を次の居場所にする。
//! 境目に遮られたときだけ `障害物に遮られた` が生じる。

use std::convert::Infallible;

use blitz_design::{M不変データ, M射影関数, M状態, M状態遷移関数, 状態遷移失敗結果, 状態遷移成功結果};

use crate::transition_parameter::状態遷移パラメータ;
use crate::walking_direction::歩行方向;
use crate::地点と経路::区域の中の移動の型::区域の中の移動の指定;
use crate::地点と経路::識別子::地点の識別子;
use crate::旅行者::{旅行者の出来事, 旅行者の意図, 旅行者の現在地, 歩行の規則, 移動の変位};
use crate::歩行の状態遷移::{旅行者の描画位置, 歩行の状態遷移の規則};

/// 旅行者がいる地点と、その地点の区域の中の現在地。
#[derive(Debug, Clone, PartialEq)]
pub struct 旅行者の居場所 {
    地点: 地点の識別子,
    現在地: 旅行者の現在地,
}

impl M不変データ for 旅行者の居場所 {}
impl M状態 for 旅行者の居場所 {}

impl 旅行者の居場所 {
    /// 地点と現在地から居場所を作る。現在地がその地点の区域の中にあるかは、状態遷移が空間制約の地図で確かめる(別の地図の地点を渡されると、状態遷移がプログラムの誤りとして停止する)。
    pub fn 生成する(地点: 地点の識別子, 現在地: 旅行者の現在地) -> Self {
        Self { 地点, 現在地 }
    }

    pub fn 地点(&self) -> &地点の識別子 {
        &self.地点
    }

    pub fn 現在地(&self) -> 旅行者の現在地 {
        self.現在地
    }

    /// 居場所を値で受け取り、意図と規則と状態遷移パラメータ(経過時間)から次の居場所と出来事を導く純粋計算(M状態遷移関数の型シグネチャを満たす)。失敗しない状態遷移である。
    /// 静止と見回すも、居場所がいる地点の区域の中にあることを先に確かめる(区域の外にいる旅行者の状態遷移を進めない)。
    pub fn 歩行を状態遷移させる(
        self,
        意図: &旅行者の意図,
        規則: &歩行の状態遷移の規則,
        パラメータ: 状態遷移パラメータ,
    ) -> Result<状態遷移成功結果<旅行者の居場所, 旅行者の出来事>, 状態遷移失敗結果<旅行者の居場所, Infallible>> {
        let 始点 = self.現在地.平面の点へ広げる();
        let 終点 = match 意図 {
            旅行者の意図::歩く { 方向 } => self.目的地(方向, 規則.身体(), パラメータ).平面の点へ広げる(),
            旅行者の意図::静止 | 旅行者の意図::見回す => 始点,
        };
        let 移動の結果 = 規則
            .空間制約()
            .区域の中で動かす(区域の中の移動の指定::生成する(self.地点, 始点, 終点))
            .unwrap_or_else(|失敗| panic!("旅行者の居場所が空間制約の区域の中に無い(旅行者は、地図に在る地点の区域の内側か境目の上にいなければならない): {失敗}"));
        let 出来事一覧 = match (意図, 移動の結果.遮られたか()) {
            (旅行者の意図::見回す, _) => vec![旅行者の出来事::周囲を観察した],
            (_, true) => vec![旅行者の出来事::障害物に遮られた],
            (_, false) => vec![],
        };
        let 次の状態 = Self {
            地点: 移動の結果.地点().clone(),
            現在地: 旅行者の現在地::平面の点から狭める(&移動の結果.到達点()).unwrap_or_else(|失敗| panic!("区域の中の移動が着いた点が旅行者の現在地にならない(着いた点は、有限で単精度に収まる座標でなければならない): {失敗}")),
        };
        Ok(状態遷移成功結果::生成する(次の状態, 出来事一覧))
    }

    // 速さと向きと経過時間から求めた、区域を考えない目的地。有限な入力の積和でも単精度は無限大になりうるため、現在地の生成の検証を通し、破れたらプログラムの誤りとして停止する。
    fn 目的地(&self, 方向: &歩行方向, 身体: &歩行の規則, パラメータ: 状態遷移パラメータ) -> 旅行者の現在地 {
        let 速さ = 身体.速さ();
        let 経過時間 = パラメータ.経過時間();
        self.現在地
            .平行移動する(移動の変位::生成する(速さ.比で伸ばす(方向.東の比率()) * 経過時間.秒(), 速さ.比で伸ばす(方向.北の比率()) * 経過時間.秒()))
            .unwrap_or_else(|失敗| panic!("歩いた先の現在地が有限な数でなくなった(次の現在地の座標は有限な数でなければならない): {失敗}"))
    }

    /// 居場所から描画用DTOを取り出す一方向の射影(M射影関数の型シグネチャを満たす)。
    pub fn 描画位置を射影する(&self) -> 旅行者の描画位置 {
        旅行者の描画位置::生成する(self.現在地.東(), self.現在地.北())
    }
}

// 歩行を状態遷移させる が状態遷移の役割(M状態・Mコマンド・M規則 から M状態・Mイベント、失敗しない)を満たすことをコンパイラに確かめさせる。
const _: M状態遷移関数<旅行者の居場所, 旅行者の意図, 歩行の状態遷移の規則, 状態遷移パラメータ, 旅行者の出来事, std::convert::Infallible> = M状態遷移関数::生成する(旅行者の居場所::歩行を状態遷移させる);

// 描画位置を射影する が射影の役割(M状態 から M不変データ)を満たすことをコンパイラに確かめさせる。
const _: M射影関数<旅行者の居場所, 旅行者の描画位置> = M射影関数::生成する(旅行者の居場所::描画位置を射影する);
