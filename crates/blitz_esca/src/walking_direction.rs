//! 旅行者が歩く向き。長さが1であることを不変条件に持つ、東と北の比率の組である。
//!
//! 生成の口はキーボードの押下状態からの導出だけである。同型の `f32` を2つ並べる生成の口を置かないのは、
//! 東と北を取り違えても型が通るためであり、試験が向きを要るときは単位方向の関連関数を使う。

use crate::traveler_input::キーボード歩行入力;

/// 正規化済みの歩く向き。東の比率と北の比率の二乗和は1である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 歩行方向 {
    東の比率: f32,
    北の比率: f32,
}

impl 歩行方向 {
    /// キーの押下状態から向きを導く。相反するキー(上下・左右)は相殺し、相殺の結果が零なら向きは無い。
    /// 斜めの入力は長さを1へ正規化する。
    pub fn キー入力から導く(入力: &キーボード歩行入力) -> Option<Self> {
        let 東 = 入力.東西の倒し量();
        let 北 = 入力.南北の倒し量();
        if 東 == 0.0 && 北 == 0.0 {
            return None;
        }
        let 長さ = (東 * 東 + 北 * 北).sqrt();
        Some(Self {
            東の比率: 東 / 長さ, 北の比率: 北 / 長さ
        })
    }

    pub const fn 東() -> Self {
        Self { 東の比率: 1.0, 北の比率: 0.0 }
    }

    pub const fn 西() -> Self {
        Self { 東の比率: -1.0, 北の比率: 0.0 }
    }

    pub const fn 北() -> Self {
        Self { 東の比率: 0.0, 北の比率: 1.0 }
    }

    pub const fn 南() -> Self {
        Self { 東の比率: 0.0, 北の比率: -1.0 }
    }

    pub fn 東の比率(&self) -> f32 {
        self.東の比率
    }

    pub fn 北の比率(&self) -> f32 {
        self.北の比率
    }
}
