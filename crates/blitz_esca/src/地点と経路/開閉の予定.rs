//! 経路の開閉の予定。ステージを作る人が経路1本ごとに置く、はじめに開いているか閉じているかと、時間によって閉じている時間帯の並びである。
//! 地点と経路のグラフの辺の積み荷(辺そのものが持つ値)として持つ。経路と予定を別の表で持たないのは、予定が地図に無い経路を指す食い違いを型で起こせなくするためである。
//! 時間帯は時刻の順に並び、互いに重ならないことを不変条件に持つ。この不変条件があるため、1本の経路について1回の刻みに来る予定の変化は、
//! 時間帯の並びの順に読めば時刻の順になり、並べ替えずに当てられる。

use blitz_design::M不変データ;

use super::時間帯::閉じている時間帯;
use crate::transition_parameter::遷移パラメータ;
use crate::時刻::世界の時刻;

/// 経路1本が開いているか閉じているか。予定のはじめの開閉と、予定が経路を変える先の開閉の両方をこの型で表す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 経路の開閉 {
    開いている,
    閉じている,
}

impl M不変データ for 経路の開閉 {}

/// 経路1本の開閉の予定。フィールドは私有であり、`生成する` の検証を通らずには作れない。
#[derive(Debug, Clone, PartialEq)]
pub struct 経路の開閉の予定 {
    はじめの開閉: 経路の開閉,
    閉じている時間帯一覧: Vec<閉じている時間帯>,
}

impl M不変データ for 経路の開閉の予定 {}

impl 経路の開閉の予定 {
    /// 時間帯が時刻の順に並び、前の時間帯の終わりが次の時間帯の始まり以前であることを確かめて予定を作る。
    /// 終わりと次の始まりが同じ時刻であることは許す(その時刻に一度開いてすぐ閉じる予定になり、順に当てれば閉じたまま残る)。
    pub fn 生成する(はじめの開閉: 経路の開閉, 閉じている時間帯一覧: Vec<閉じている時間帯>) -> Result<Self, 経路の開閉の予定の生成の失敗> {
        for (前, 次) in 閉じている時間帯一覧.iter().zip(閉じている時間帯一覧.iter().skip(1)) {
            if 前.終わり() > 次.始まり() {
                return Err(経路の開閉の予定の生成の失敗::時間帯が時刻の順に並んでいない {
                    前の終わり: 前.終わり(),
                    次の始まり: 次.始まり(),
                });
            }
        }
        Ok(Self {
            はじめの開閉, 閉じている時間帯一覧
        })
    }

    /// 時間による閉鎖を持たない予定。
    pub fn 時間帯を持たない(はじめの開閉: 経路の開閉) -> Self {
        Self {
            はじめの開閉,
            閉じている時間帯一覧: Vec::new(),
        }
    }

    pub fn はじめの開閉(&self) -> 経路の開閉 {
        self.はじめの開閉
    }

    /// 閉じている時間帯を1つ以上持つか。
    pub fn 時間帯を持つか(&self) -> bool {
        !self.閉じている時間帯一覧.is_empty()
    }

    /// この刻みに来る予定の変化を、時刻の順に並べる。時間帯の始まりが来れば閉じている、終わりが来れば開いているへ変える。
    /// 刻みごとに経路の本数だけ呼ばれるため、並びを確保せず反復子で返す。
    pub fn この刻みに来る変化一覧(&self, パラメータ: 遷移パラメータ) -> impl Iterator<Item = 経路の開閉> + '_ {
        self.閉じている時間帯一覧.iter().flat_map(move |時間帯| {
            let 閉じる = パラメータ.その時刻がこの刻みに来るか(時間帯.始まり()).then_some(経路の開閉::閉じている);
            let 開く = パラメータ.その時刻がこの刻みに来るか(時間帯.終わり()).then_some(経路の開閉::開いている);
            閉じる.into_iter().chain(開く)
        })
    }
}

/// 経路の開閉の予定が不変条件を満たさなかった理由。
#[derive(Debug, Clone, Copy, PartialEq, thiserror::Error)]
pub enum 経路の開閉の予定の生成の失敗 {
    #[error("前の時間帯の終わり{前の終わり:?}が次の時間帯の始まり{次の始まり:?}より後である(閉じている時間帯は時刻の順に並び、互いに重なってはならない)")]
    時間帯が時刻の順に並んでいない { 前の終わり: 世界の時刻, 次の始まり: 世界の時刻 },
}
