//! 区域の中の移動の指定と結果と失敗。区域の中の移動(`区域の中の移動.rs`)が受け取り、返す値である。
//! 工程の本体と分けるのは、本体が移動の途中の状態と手順を持ち、こちらが工程の外へ出る値の形だけを持つためである。

use blitz_design::M不変データ;

use super::識別子::地点の識別子;
use crate::平面の幾何::点と線分::平面の点;

/// 区域の中の移動の指定。旅行者がいる地点と、その地点の区域の閉包の中の始点と、動こうとする終点を持つ。
#[derive(Debug, Clone, PartialEq)]
pub struct 区域の中の移動の指定 {
    pub 地点: 地点の識別子,
    pub 始点: 平面の点,
    pub 終点: 平面の点,
}

impl M不変データ for 区域の中の移動の指定 {}

/// 区域の中の移動の結果。着いた地点と、着いた点と、途中で境目に遮られたかを持つ。
#[derive(Debug, Clone, PartialEq)]
pub struct 区域の中の移動の結果 {
    pub 地点: 地点の識別子,
    pub 到達点: 平面の点,
    pub 遮られたか: bool,
}

impl M不変データ for 区域の中の移動の結果 {}

/// 区域の中の移動を始められなかった理由。
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum 区域の中の移動の失敗 {
    #[error("地点{地点:?}が地図に無い(旅行者がいる地点は、空間制約の地図に在る地点でなければならない)")]
    地図に無い地点にいる { 地点: 地点の識別子 },
    #[error("始点{始点:?}が地点{地点:?}の区域の外にある(旅行者の現在地は、いる地点の区域の内側か境目の上になければならない)")]
    始点が地点の区域の外にある { 地点: 地点の識別子, 始点: 平面の点 },
}
