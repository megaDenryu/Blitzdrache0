//! 経路の開閉の出来事。開閉の遷移によって、経路が実際に閉じた・開いたという過去の事実である。
//! 出来事は遷移の前の状態と次の状態の差からだけ組む(設計オントロジー 4.4 の法則E2)。すでに閉じている経路を閉じる命令も、
//! 同じ刻みで時刻が閉じて命令が開いた経路も、前後で開閉が変わらないため出来事を生まない。
//! 出来事はきっかけ(時刻か命令か)を持たない。前後の差だけが成立した事実であり、きっかけは1つの刻みの中で重なりうるためである。

use blitz_design::{Mイベント, M不変データ};

use super::封鎖できる経路::封鎖できる経路の識別子;
use super::開閉の予定::経路の開閉;

/// 開閉の遷移で成立した事実。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 経路の開閉の出来事 {
    /// 遷移の前に開いていた経路が、遷移の後に閉じている事実。
    経路が閉じた { 経路: 封鎖できる経路の識別子 },
    /// 遷移の前に閉じていた経路が、遷移の後に開いている事実。
    経路が開いた { 経路: 封鎖できる経路の識別子 },
}

impl M不変データ for 経路の開閉の出来事 {}
impl Mイベント for 経路の開閉の出来事 {}

impl 経路の開閉の出来事 {
    /// 経路1本の遷移の前後の開閉から出来事を組む。前後が同じなら事実は成立していないため無しである。
    pub(super) fn 前後の開閉の差から組む(経路: 封鎖できる経路の識別子, 前: 経路の開閉, 後: 経路の開閉) -> Option<Self> {
        match (前, 後) {
            (経路の開閉::開いている, 経路の開閉::閉じている) => Some(Self::経路が閉じた { 経路 }),
            (経路の開閉::閉じている, 経路の開閉::開いている) => Some(Self::経路が開いた { 経路 }),
            (経路の開閉::開いている, 経路の開閉::開いている) | (経路の開閉::閉じている, 経路の開閉::閉じている) => None,
        }
    }
}
