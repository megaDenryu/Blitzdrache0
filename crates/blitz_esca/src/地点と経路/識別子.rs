//! 地点の識別子と経路の識別子。地図(`地点と経路のグラフ`)が、その地点・経路が自分の中に在ることを確かめてから渡す値である。
//! Graphiteが生成する識別子(`地点Id`・`経路Id`)は中身の文字列が公開されており、誰でも任意の文字列から作れる。それをそのまま状態や命令へ入れると、
//! 地図に無い地点・経路を指す値が型の上で作れてしまう。そのためこのモジュールの外では作れない型で包み、作る口を地図だけに渡す。
//! 別の地図が渡した識別子は型の上では区別できないため、遷移はその識別子が規則の地図に在ることを改めて確かめる。
//! 経路の識別子は、閉じている経路の集合の要素として並びが決まる必要があるため、中身の文字列の順で全順序を持つ。

use std::cmp::Ordering;

use blitz_design::{M不変データ, M値オブジェクト};

use super::図式::地点と経路の図式::{地点Id, 経路Id};

/// 地図が在ることを確かめた地点を指す識別子。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct 地点の識別子(地点Id);

impl M不変データ for 地点の識別子 {}
impl M値オブジェクト for 地点の識別子 {}

impl 地点の識別子 {
    /// 地図が自分の中に在ることを確かめた図式の識別子を包む。地図のモジュールだけが呼ぶ。
    pub(super) fn 確かめた図式の識別子から作る(識別子: 地点Id) -> Self {
        Self(識別子)
    }

    /// 人が読む表記。図式の識別子の中身の文字列である。
    pub fn 表記(&self) -> &str {
        &self.0.0
    }
}

/// 地図が在ることを確かめた経路を指す識別子。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct 経路の識別子(経路Id);

impl M不変データ for 経路の識別子 {}
impl M値オブジェクト for 経路の識別子 {}

impl 経路の識別子 {
    /// 地図が自分の中に在ることを確かめた図式の識別子を包む。地図のモジュールだけが呼ぶ。
    pub(super) fn 確かめた図式の識別子から作る(識別子: 経路Id) -> Self {
        Self(識別子)
    }

    /// 包んでいる図式の識別子。地図が自分の中を引くときにだけ使う。
    pub(super) fn 図式の識別子(&self) -> &経路Id {
        &self.0
    }

    /// 人が読む表記。図式の識別子の中身の文字列である。
    pub fn 表記(&self) -> &str {
        &self.0.0
    }
}

impl PartialOrd for 経路の識別子 {
    fn partial_cmp(&self, 右辺: &Self) -> Option<Ordering> {
        Some(self.cmp(右辺))
    }
}

impl Ord for 経路の識別子 {
    /// 中身の文字列の順。等しさ(導出した `Eq`)も中身の文字列の一致であるため、2つは食い違わない。
    fn cmp(&self, 右辺: &Self) -> Ordering {
        self.表記().cmp(右辺.表記())
    }
}
