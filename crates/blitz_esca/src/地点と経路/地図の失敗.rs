//! 地図の生成の失敗。Graphiteの完成したグラフが、地点と経路のグラフ(地図)の不変条件を満たさなかった理由である。
//! 多重度と端点の検査はGraphiteの凍結が済ませているため、ここに並ぶのは区域と通り口と経路の種類の食い違いだけである。

use blitz_design::{M不変データ, M値オブジェクト};

use super::種類::経路の種類;
use super::識別子::{地点の識別子, 経路の識別子};

/// 地図の不変条件が破れた理由。
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum 地図の生成の失敗 {
    #[error("地点{一方の地点:?}と地点{もう一方の地点:?}の区域の内部が重なっている(区域どうしは境目だけを共有し、内部が重なってはならない)")]
    区域の内部が重なっている { 一方の地点: 地点の識別子, もう一方の地点: 地点の識別子 },
    #[error("経路{経路:?}の両端が同じ地点である(経路は2つの異なる地点の区域の境目を越える箇所でなければならない)")]
    経路の両端が同じ地点である { 経路: 経路の識別子 },
    #[error("封鎖できない種類({種類:?})の経路{経路:?}が、はじめから閉じているか閉じている時間帯を持つ(閉じる予定を持てるのは幹線道路・橋・門だけである)")]
    封鎖できない経路が閉じる予定を持つ { 経路: 経路の識別子, 種類: 経路の種類 },
    #[error("経路{経路:?}の通り口の2つの辺の番号が、両端の区域の共有する辺を指していない(頂点が完全に一致し逆向きに張られた辺でなければならない)")]
    通り口の辺が両端の区域に共有されていない { 経路: 経路の識別子 },
    #[error("経路{経路:?}の通り口の2つの辺の番号を、両端の区域のどちらへ当てても共有する辺になり、どちらの区域の辺か決まらない")]
    通り口の辺がどちらの区域の辺か決まらない { 経路: 経路の識別子 },
    #[error("経路{一方の経路:?}と経路{もう一方の経路:?}の通り口が同じ区域の同じ辺にあり重なっている(通り口どうしは重なってはならない)")]
    通り口どうしが重なっている { 一方の経路: 経路の識別子, もう一方の経路: 経路の識別子 },
}

impl M不変データ for 地図の生成の失敗 {}
impl M値オブジェクト for 地図の生成の失敗 {}
