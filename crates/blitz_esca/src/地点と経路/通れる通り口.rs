//! 通れる通り口の集合。経路の開閉の状態と地図から刻みごとに導く、いま開いている通り口の並びである(`経路の開閉の状態::通れる通り口を導く`)。
//! 歩行の遷移は、これを地図の区域と一緒に歩行の規則の空間制約として読み取り専用で受け取る。別の仕組み(経路の開閉)が持つ状態から刻みごとに作った読み取り専用の値は、
//! その遷移の規則(`M規則`)の一部として渡してよい。規則の「変わらない」は1回の遷移の評価のあいだ読み取り専用であることを指すためである(2026-09-26 オーナー裁定。設計オントロジー 3.5.2)。
//! この値を `M観測` として渡さないのは、観測は遷移の因果の入力へ戻してはならないためである。

use blitz_design::M不変データ;

use super::識別子::地点の識別子;
use super::通り口::{区域の辺の所在, 確かめた通り口};

/// いま開いている通り口の並び。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 通れる通り口の集合 {
    通り口一覧: Vec<確かめた通り口>,
}

impl M不変データ for 通れる通り口の集合 {}

impl 通れる通り口の集合 {
    /// 開いている通り口から集合を作る。呼ぶのは経路の開閉の状態の導く口だけである。
    pub(super) fn 開いた通り口から作る(通り口一覧: Vec<確かめた通り口>) -> Self {
        Self { 通り口一覧 }
    }

    /// その区域の辺にいま開いている通り口があれば、そこを抜けた先の地点。無ければ無しである。
    pub fn その辺から抜けた先(&self, 辺: &区域の辺の所在) -> Option<&地点の識別子> {
        self.通り口一覧.iter().find_map(|通り口| 通り口.その辺から抜けた先(辺))
    }

    /// いま開いている通り口を、地図が並べた順に並べる。
    pub fn 通り口一覧(&self) -> &[確かめた通り口] {
        &self.通り口一覧
    }
}
