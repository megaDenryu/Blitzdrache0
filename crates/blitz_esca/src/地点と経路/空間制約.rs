//! 区域の空間制約。歩行の遷移が読み取り専用で受け取る、地図の区域と、いまどの通り口が通れるかを決める経路の開閉の状態の組である(設計正本 4.4 条2 の空間制約)。
//! 地図は `M共有される不変データ` であり、複製せず `Arc` で共有して持つ。そのため刻みごとにこの値を作っても、地図の複製は起きず、`Arc` の数が1つ増えるだけである。
//! 開閉の状態は値で受け取って持ち、歩行の遷移の後に `開閉の状態を取り出す` で持ち主へ返す。刻みごとに開閉の状態を複製しないためである。
//! 通り口がいま開いているかは、読むときに開閉の状態へ問う。通れる通り口を並べた値を刻みごとに作ると、刻みごとに並びの確保と識別子の文字列の複製がかかるためである。
//! 作る口は、開閉の状態の経路がこの地図に在ることを確かめ、食い違えば失敗する。別の地図の開閉の状態と組むと、閉じている門を開いていると判断するためである。
//! 外から渡された地図と状態を検証する口であるため、食い違いは型付きの失敗で返す。
//! 区域の中の移動(境目で滑る・通り口を抜ける)は `区域の中で動かす` が入口であり、手順は `区域の中の移動.rs` が持つ。

use std::sync::Arc;

use blitz_design::{M不変データ, M値オブジェクト, M規則};

use super::区域の中の移動::移動の途中;
use super::区域の中の移動の型::{区域の中の移動の失敗, 区域の中の移動の指定, 区域の中の移動の結果};
use super::地図::地点と経路のグラフ;
use super::指定の失敗::経路の指定の失敗;
use super::識別子::地点の識別子;
use super::通り口::確かめた通り口;
use super::開閉の状態::経路の開閉の状態;
use crate::平面の幾何::多角形::単純多角形;
use crate::平面の幾何::点と線分::平面の点;

/// 地図の区域と、その地図で確かめた経路の開閉の状態。
#[derive(Clone)]
pub struct 区域の空間制約 {
    地図: Arc<地点と経路のグラフ>,
    開閉の状態: 経路の開閉の状態,
}

impl M不変データ for 区域の空間制約 {}
impl M規則 for 区域の空間制約 {}

impl 区域の空間制約 {
    /// 共有する地図と、その地図の経路の開閉の状態から空間制約を作る。状態の経路が地図に無ければ失敗する。
    pub fn 開閉の状態から導く(地図: Arc<地点と経路のグラフ>, 開閉の状態: 経路の開閉の状態) -> Result<Self, 経路の指定の失敗> {
        開閉の状態.経路がどれも地図に在ることを確かめる(&地図)?;
        Ok(Self { 地図, 開閉の状態 })
    }

    pub fn 地図(&self) -> &地点と経路のグラフ {
        &self.地図
    }

    /// 空間制約を解き、作るときに受け取った開閉の状態を返す。経路の開閉と旅行者の歩行の遷移が、歩行の後に開閉の状態を複製せずに次の状態へ戻すための口である。
    pub fn 開閉の状態を取り出す(self) -> 経路の開閉の状態 {
        self.開閉の状態
    }

    /// 地図が確かめた通り口のうち、いま開いているものを地図が並べた順に並べる。並びを確保せず、読むたびに開閉の状態へ問う。
    pub fn 開いている通り口一覧(&self) -> impl Iterator<Item = &確かめた通り口> {
        self.地図.通り口一覧().iter().filter(|通り口| self.開閉の状態.通り口が開いているか(通り口))
    }

    /// 地点の区域の中の始点から終点へ動かし、境目で滑るか通り口を抜けた後に着いた地点と点を返す。始点が地点の区域の閉包に無ければ失敗する。
    pub fn 区域の中で動かす(&self, 指定: 区域の中の移動の指定) -> Result<区域の中の移動の結果, 区域の中の移動の失敗> {
        移動の途中::始める(self, 指定)?.着くまで進める(self)
    }

    /// その地点の区域の多角形。区域の中の移動が、いる地点の区域を読むために呼ぶ。地点がこの地図に無ければ失敗する。
    pub(super) fn 地点の多角形(&self, 地点: &地点の識別子) -> Result<&単純多角形, 区域の中の移動の失敗> {
        self.地図.地点の区域を読む(地点).map(|区域| 区域.多角形()).ok_or_else(|| 区域の中の移動の失敗::地図に無い地点にいる { 地点: 地点.clone() })
    }

    /// 点を閉包(内側か境界の上)に含む区域の地点を1つに決める。どの区域にも入らなければ世界の外であり、2つ以上の区域の境目の上にあれば決まらない。
    /// 旅行者を置く最初の居場所を現在地から決めるための口であり、置いた後の所属は歩行の遷移が居場所として持ち運ぶ。
    pub fn 点を含む地点を決める(&self, 点: &平面の点) -> Result<地点の識別子, 地点を決められない理由> {
        let 含む地点一覧: Vec<地点の識別子> = self.地図.地点の識別子一覧().into_iter().filter(|地点| self.地図.地点の区域を読む(地点).is_some_and(|区域| 区域.多角形().閉包に入るか(点))).collect();
        match 含む地点一覧.as_slice() {
            [] => Err(地点を決められない理由::世界の外にある),
            [ただ1つ] => Ok(ただ1つ.clone()),
            _ => Err(地点を決められない理由::区域の境目の上にある {
                境目を持つ地点一覧: 含む地点一覧
            }),
        }
    }
}

/// 点から地点を1つに決められなかった理由。
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum 地点を決められない理由 {
    #[error("点がどの区域にも入らない(世界の外である)")]
    世界の外にある,
    #[error("点が地点{境目を持つ地点一覧:?}の区域の境目の上にあり、どの地点にいるかを点だけからは決められない")]
    区域の境目の上にある { 境目を持つ地点一覧: Vec<地点の識別子> },
}

impl M不変データ for 地点を決められない理由 {}
impl M値オブジェクト for 地点を決められない理由 {}
