//! 封鎖できる経路の識別子。地図(`地点と経路のグラフ`)が、その経路が自分の中に在り、しかも種類が封鎖できる経路であることを確かめてから渡す値である。
//! 経路の開閉の命令・状態・出来事はこの型で経路を指す。封鎖できない経路(脇道・山道)を閉じる命令を、型の上で作れないようにするためである(2026-09-26 オーナー裁定)。
//! 作る口の可視性は `pub(super)` であり、呼ぶのは地図と開閉の規則と地図の検証(`地図の検証.rs`)だけである(`識別子.rs` の冒頭と同じ規約)。
//! 閉じている経路の集合の要素として並びが決まる必要があるため、中身の文字列の順で全順序を持つ。

use std::cmp::Ordering;

use blitz_design::{M不変データ, M値オブジェクト};

use super::図式::地点と経路の図式::経路Id;
use super::識別子::経路の識別子;

/// 地図が在ることと封鎖できることを確かめた経路を指す識別子。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct 封鎖できる経路の識別子(経路Id);

impl M不変データ for 封鎖できる経路の識別子 {}
impl M値オブジェクト for 封鎖できる経路の識別子 {}

impl 封鎖できる経路の識別子 {
    /// 地図が自分の中から取り出した、封鎖できる種類の経路の図式の識別子を包む。呼ぶのは地図と開閉の規則だけである。
    pub(super) fn 確かめた図式の識別子から作る(識別子: 経路Id) -> Self {
        Self(識別子)
    }

    /// 包んでいる図式の識別子。地図が自分の中を引くときにだけ使う。
    pub(super) fn 図式の識別子(&self) -> &経路Id {
        &self.0
    }

    /// 同じ経路を、種類を問わない経路の識別子として指す。
    pub fn 経路の識別子(&self) -> 経路の識別子 {
        経路の識別子::確かめた図式の識別子から作る(self.0.clone())
    }

    /// 人が読む表記。図式の識別子の中身の文字列である。
    pub fn 表記(&self) -> &str {
        &self.0.0
    }
}

impl PartialOrd for 封鎖できる経路の識別子 {
    fn partial_cmp(&self, 右辺: &Self) -> Option<Ordering> {
        Some(self.cmp(右辺))
    }
}

impl Ord for 封鎖できる経路の識別子 {
    /// 中身の文字列の順。等しさ(導出した `Eq`)も中身の文字列の一致であるため、2つは食い違わない。
    fn cmp(&self, 右辺: &Self) -> Ordering {
        self.表記().cmp(右辺.表記())
    }
}
