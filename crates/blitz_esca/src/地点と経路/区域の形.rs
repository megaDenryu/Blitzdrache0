//! 区域。地面を上から見た多角形であり、地点が世界のどの範囲かを表す。ステージを作る人が1つずつ描く(2026-09-26 オーナー裁定)。
//! 区域の境目は、越えられない地形(川・崖・城壁・山並み)に沿って描き、開けた野原でつながる場所は同じ区域にする。境目を越えられるのは経路の通り口だけである。
//! 区域は自己交差せず、頂点が反時計回りに並び、頂点が3つ以上の単純多角形であることを不変条件に持ち、公開フィールドの指定を検証して初めて得られる。
//! 多角形の計算は仕組みの層(`平面の幾何`)に置き、この型はそれを包んでEscaの語彙で呼ぶ(設計正本 4.3)。

use blitz_design::{MParameter, M不変データ, M値オブジェクト, M関数への入力};
use blitz_math::{メートル, 大域メートル};

use crate::平面の幾何::多角形::{単純多角形, 単純多角形の生成の失敗};
use crate::平面の幾何::点と線分::平面の点;

/// 区域の頂点1つ。東と北をメートルで持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 区域の頂点 {
    pub 東: メートル,
    pub 北: メートル,
}

impl M不変データ for 区域の頂点 {}
impl M値オブジェクト for 区域の頂点 {}

/// 区域を作るための指定。頂点を北を上に見て反時計回りに並べる。検証を通ると区域になる。
#[derive(Debug, Clone, PartialEq)]
pub struct 区域の指定 {
    pub 頂点一覧: Vec<区域の頂点>,
}

impl M不変データ for 区域の指定 {}
impl M関数への入力 for 区域の指定 {}
impl MParameter for 区域の指定 {}
impl M値オブジェクト for 区域の指定 {}

impl 区域の指定 {
    /// 頂点の並びが単純多角形であることを確かめて区域を作る。
    pub fn 検証する(self) -> Result<区域, 単純多角形の生成の失敗> {
        let 頂点一覧 = self.頂点一覧.iter().map(区域の頂点::平面の点へ広げる).collect();
        Ok(区域 {
            多角形: 単純多角形::検証する(頂点一覧)?
        })
    }
}

impl 区域の頂点 {
    fn 平面の点へ広げる(&self) -> 平面の点 {
        平面の点 {
            東: 大域メートル::メートルから広げる(self.東),
            北: 大域メートル::メートルから広げる(self.北),
        }
    }
}

/// 地面を上から見た、地点の範囲。
#[derive(Debug, Clone, PartialEq)]
pub struct 区域 {
    多角形: 単純多角形,
}

impl M不変データ for 区域 {}
impl M値オブジェクト for 区域 {}

impl 区域 {
    /// 区域の形の多角形。区域の中の移動と地図の検証が、多角形の計算を呼ぶために読む。
    pub fn 多角形(&self) -> &単純多角形 {
        &self.多角形
    }
}
