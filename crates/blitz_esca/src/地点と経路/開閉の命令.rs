//! 経路の開閉の命令。出来事をきっかけに経路を閉じる・開くことを、開閉の遷移へ求める値である。
//! 出来事からこの命令を作るのはイベント反応(設計オントロジー 3.5.7)であり、第3段階で作る。ここは命令を受け取る側だけを持つ。
//! 時間による開閉は命令でなく、遷移パラメータの時刻から規則が判断する。そのため時刻だけを進める刻みのために `命令が無い` の選択肢を持つ。

use blitz_design::{Mコマンド, M不変データ};

use super::識別子::経路の識別子;
use super::開閉の予定::経路の開閉;
use super::開閉の規則::経路の開閉の変化;

/// 開閉の遷移へ与える命令。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 経路の開閉の命令 {
    経路を閉じる { 経路: 経路の識別子 },
    経路を開く { 経路: 経路の識別子 },
    命令が無い,
}

impl M不変データ for 経路の開閉の命令 {}
impl Mコマンド for 経路の開閉の命令 {}

impl 経路の開閉の命令 {
    /// 命令が指す経路。命令が無ければ無しである。
    pub fn 指す経路(&self) -> Option<&経路の識別子> {
        match self {
            Self::経路を閉じる { 経路 } | Self::経路を開く { 経路 } => Some(経路),
            Self::命令が無い => None,
        }
    }

    /// 命令が求める開閉の変化。命令が無ければ無しである。
    pub(super) fn 開閉の変化(&self) -> Option<経路の開閉の変化> {
        match self {
            Self::経路を閉じる { 経路 } => Some(経路の開閉の変化 {
                経路: 経路.clone(),
                変わる先: 経路の開閉::閉じている,
            }),
            Self::経路を開く { 経路 } => Some(経路の開閉の変化 {
                経路: 経路.clone(),
                変わる先: 経路の開閉::開いている,
            }),
            Self::命令が無い => None,
        }
    }
}
