//! 区域の空間制約の読み口。地図の区域と、経路の開閉の状態を、持ち主から借りて読む口であり、区域の中の移動(`区域の中の移動.rs`)の入口を持つ。
//! 通り口がいま開いているかは、読むときに開閉の状態へ問う。通れる通り口を並べた値を刻みごとに作ると、刻みごとに並びの確保と識別子の文字列の複製がかかるためである。
//! 所有する空間制約(`区域の空間制約`。`M規則`)と別に置くのは、経路の開閉と旅行者の歩行の遷移が、規則が持つ地図と状態が持つ開閉を複製せずに歩行を進めるためである。
//! 参照を持つため設計解釈マーカーを名乗らない。1回の歩行の遷移の中だけで作って捨てる口であり、状態にも規則にも保持されない。
//! 注意: 作る口は `地点と経路` の中だけに開き、開閉の状態の経路を同じ地図で確かめた後にだけ呼ぶ(`経路の開閉の規則::空間制約の読み口を作る`・`区域の空間制約::読み口`)。
//! 別の地図の状態と組むと、閉じている門を開いていると判断する。

use super::区域の中の移動::移動の途中;
use super::区域の中の移動の型::{区域の中の移動の失敗, 区域の中の移動の指定, 区域の中の移動の結果};
use super::地図::地点と経路のグラフ;
use super::識別子::地点の識別子;
use super::通り口::確かめた通り口;
use super::開閉の状態::経路の開閉の状態;
use crate::平面の幾何::多角形::単純多角形;

/// 地図の区域と、経路の開閉の状態を借りて読む口。
#[derive(Clone, Copy)]
pub struct 区域の空間制約の読み口<'a> {
    地図: &'a 地点と経路のグラフ,
    開閉の状態: &'a 経路の開閉の状態,
}

impl<'a> 区域の空間制約の読み口<'a> {
    /// 地図と、その地図で経路を確かめた経路の開閉の状態を借りる。
    pub(super) fn 確かめた取り合わせから作る(地図: &'a 地点と経路のグラフ, 開閉の状態: &'a 経路の開閉の状態) -> Self {
        Self { 地図, 開閉の状態 }
    }

    pub fn 地図(&self) -> &'a 地点と経路のグラフ {
        self.地図
    }

    /// 地図が確かめた通り口のうち、いま開いているものを地図が並べた順に並べる。並びを確保せず、読むたびに開閉の状態へ問う。
    pub fn 開いている通り口一覧(&self) -> impl Iterator<Item = &'a 確かめた通り口> + 'a {
        let 開閉の状態 = self.開閉の状態;
        self.地図.通り口一覧().iter().filter(move |通り口| 開閉の状態.通り口が開いているか(通り口))
    }

    /// 地点の区域の中の始点から終点へ動かし、境目で滑るか通り口を抜けた後に着いた地点と点を返す。始点が地点の区域の閉包に無ければ失敗する。
    pub fn 区域の中で動かす(self, 指定: 区域の中の移動の指定) -> Result<区域の中の移動の結果, 区域の中の移動の失敗> {
        移動の途中::始める(self, 指定)?.着くまで進める(self)
    }

    /// その地点の区域の多角形。区域の中の移動が、いる地点の区域を読むために呼ぶ。地点がこの地図に無ければ失敗する。
    pub(super) fn 地点の多角形(&self, 地点: &地点の識別子) -> Result<&'a 単純多角形, 区域の中の移動の失敗> {
        self.地図.地点の区域を読む(地点).map(|区域| 区域.多角形()).ok_or_else(|| 区域の中の移動の失敗::地図に無い地点にいる { 地点: 地点.clone() })
    }
}
