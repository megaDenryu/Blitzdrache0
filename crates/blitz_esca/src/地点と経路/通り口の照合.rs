//! 通り口の照合。経路の通り口の指定の2つの辺の番号を、経路の両端の区域へ当て、両端の区域が共有する辺かを確かめる工程と、
//! 同じ区域の同じ辺を2本の経路の通り口が使っていないかを確かめる工程を持つ。地図の検証(`地図の検証.rs`)が呼ぶ。
//! 切り出しの根拠は、呼び出し連鎖の中の独立した工程である(CLAUDE.md「切り出しの根拠義務」の5号)。
//! 当てる向きを2通り試すのは、Graphiteの向きの無い辺が両端の順序を保たず、指定のどちらの番号がどちらの区域の辺かを経路の宣言から決められないためである。
//! 2つの区域が共有する辺は、頂点の座標が完全に一致し逆向きに張られた辺である(区域の頂点は反時計回りに並ぶため)。

use std::collections::BTreeMap;

use super::図式::地点と経路の図式::経路Ref;
use super::地図の生成の失敗::地図の生成の失敗;
use super::識別子::経路の識別子;
use super::通り口::{区域の辺の所在, 区域の辺の番号, 確かめた通り口};

/// 通り口の指定の2つの番号を、経路の両端の区域へ当てた結果。一方の区域の辺は、Graphiteが経路の両端を返す順の1つ目の地点の区域の辺である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 通り口の辺の当て方 {
    pub(super) 一方の区域の辺: 区域の辺の番号,
    pub(super) もう一方の区域の辺: 区域の辺の番号,
}

impl 通り口の辺の当て方 {
    /// 通り口の指定の2つの番号を、そのままの向きと入れ替えた向きで両端の区域へ当て、共有する辺になる向きを1つに決める。
    pub(super) fn 経路の両端の区域と照らして当てる(経路: 経路Ref<'_>) -> Result<Self, 地図の生成の失敗> {
        let 指定 = 経路.積み荷().通り口();
        let そのまま = Self {
            一方の区域の辺: 指定.片方の区域の辺,
            もう一方の区域の辺: 指定.もう片方の区域の辺,
        };
        let 入れ替え = Self {
            一方の区域の辺: 指定.もう片方の区域の辺,
            もう一方の区域の辺: 指定.片方の区域の辺,
        };
        let 識別子 = 経路の識別子::確かめた図式の識別子から作る(経路.id().clone());
        match (そのまま.両端の区域に共有されるか(経路), 入れ替え.両端の区域に共有されるか(経路)) {
            (true, false) => Ok(そのまま),
            (false, true) => Ok(入れ替え),
            (true, true) if そのまま == 入れ替え => Ok(そのまま),
            (true, true) => Err(地図の生成の失敗::通り口の辺がどちらの区域の辺か決まらない { 経路: 識別子 }),
            (false, false) => Err(地図の生成の失敗::通り口の辺が両端の区域に共有されていない { 経路: 識別子 }),
        }
    }

    // この当て方の2つの辺が、両端の区域の頂点の完全に一致する逆向きの辺であるか。番号がどちらかの区域に無ければ偽である。
    fn 両端の区域に共有されるか(&self, 経路: 経路Ref<'_>) -> bool {
        let (一方, もう一方) = 経路.endpoints();
        let 一方の辺 = 一方.value().区域().多角形().辺(self.一方の区域の辺.始まりの頂点の番号());
        let もう一方の辺 = もう一方.value().区域().多角形().辺(self.もう一方の区域の辺.始まりの頂点の番号());
        match (一方の辺, もう一方の辺) {
            (Some(甲), Some(乙)) => 甲.始点 == 乙.終点 && 甲.終点 == 乙.始点,
            _ => false,
        }
    }
}

/// 同じ区域の同じ辺を2本の経路の通り口が使っていないかを確かめる。使っていれば、先に使った経路と後の経路を失敗の理由にする。
/// 依存を持たない純粋な確かめであり、主語になる型が無いため自由関数で持つ。
pub(super) fn 通り口どうしの重なりを確かめる(通り口一覧: &[確かめた通り口]) -> Result<(), 地図の生成の失敗> {
    let mut 使った辺: BTreeMap<&区域の辺の所在, &経路の識別子> = BTreeMap::new();
    for 通り口 in 通り口一覧 {
        for 辺 in 通り口.両側() {
            if let Some(先の経路) = 使った辺.insert(辺, 通り口.経路()) {
                return Err(地図の生成の失敗::通り口どうしが重なっている {
                    一方の経路: 先の経路.clone(),
                    もう一方の経路: 通り口.経路().clone(),
                });
            }
        }
    }
    Ok(())
}
