//! 経路の積み荷。地点と経路のグラフの辺(経路)が持つ値であり、経路の種類と、通り口の指定と、開閉の予定の3つを持つ。
//! 3つを辺の積み荷として経路と一緒に持つのは、種類・通り口・予定が地図に無い経路を指す食い違いを型で起こせなくするためである。
//! 封鎖できない種類の経路がはじめから閉じた予定や時間帯を持つことは、この型では拒まず、地図の検証(`地点と経路のグラフ::検証して生成する`)が拒む。
//! 3つがそろって初めて判定できる食い違いであり、地図の検証がほかの経路と区域の検査と同じ場所で報告するためである。

use blitz_design::{M不変データ, M値オブジェクト};

use super::種類::経路の種類;
use super::通り口::通り口の指定;
use super::開閉の予定::{経路の開閉, 経路の開閉の予定};

/// 経路1本の種類・通り口・開閉の予定。
#[derive(Debug, Clone, PartialEq)]
pub struct 経路の積み荷 {
    種類: 経路の種類,
    通り口: 通り口の指定,
    予定: 経路の開閉の予定,
}

impl M不変データ for 経路の積み荷 {}
impl M値オブジェクト for 経路の積み荷 {}

impl 経路の積み荷 {
    pub fn 生成する(種類: 経路の種類, 通り口: 通り口の指定, 予定: 経路の開閉の予定) -> Self {
        Self { 種類, 通り口, 予定 }
    }

    /// はじめに開いていて時間帯を持たない予定の積み荷。封鎖できない種類の経路が持てる予定はこれだけである。
    pub fn 予定を持たずに生成する(種類: 経路の種類, 通り口: 通り口の指定) -> Self {
        Self {
            種類,
            通り口,
            予定: 経路の開閉の予定::時間帯を持たない(経路の開閉::開いている),
        }
    }

    pub fn 種類(&self) -> 経路の種類 {
        self.種類
    }

    pub fn 通り口(&self) -> 通り口の指定 {
        self.通り口
    }

    pub fn 予定(&self) -> &経路の開閉の予定 {
        &self.予定
    }
}
