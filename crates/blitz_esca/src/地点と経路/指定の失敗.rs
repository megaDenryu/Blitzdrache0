//! 経路の指定の失敗。地図に無い封鎖できる経路を指した値を、経路の開閉の状態の生成と開閉の遷移が拒む理由である。
//! 封鎖できる経路の識別子は地図が確かめてから渡すが、別の地図が渡した識別子は型の上で区別できないため、受け取る側が自分の地図で改めて確かめる。

use super::封鎖できる経路::封鎖できる経路の識別子;

/// 経路の指定が地図と食い違った理由。
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum 経路の指定の失敗 {
    #[error("経路{経路:?}は地図に無い(経路の開閉の状態と開閉の命令が指す経路は、規則の地図に在る封鎖できる経路でなければならない)")]
    地図に無い経路を指した { 経路: 封鎖できる経路の識別子 },
}
