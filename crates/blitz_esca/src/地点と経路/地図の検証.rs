//! 地図の検証。Graphiteの完成したグラフを、区域と通り口と経路の種類の不変条件で確かめてから地図(`地点と経路のグラフ`)にする工程である。
//! 検証の途中のグラフを `未検証の地図` として持つのは、確かめる前のグラフを地図の型へ漏らさないためである(ビルダーの既定。完成した型が持ってはならない半端な状態をこの型が引き受ける)。
//! 確かめることは4つである。区域どうしの内部が重ならない。経路の両端が別の地点である。封鎖できない種類の経路が閉じる予定を持たない。
//! 通り口が両端の区域の共有する辺を指し、同じ区域の同じ辺を2本の経路が使わない。辺の頂点は区域の頂点の座標そのものであるため、共有する辺は座標の完全な一致で確かめる。

use super::図式::地点と経路の図式::{Graph, 経路Ref};
use super::地図::地点と経路のグラフ;
use super::地図の失敗::地図の生成の失敗;
use super::封鎖できる経路::封鎖できる経路の識別子;
use super::識別子::{地点の識別子, 経路の識別子};
use super::通り口::{区域の辺の所在, 確かめた通り口, 通り口の開閉の対象};
use super::通り口の照合::{通り口どうしの重なりを確かめる, 通り口の辺の当て方};
use super::開閉の予定::経路の開閉;

/// 地図の不変条件をまだ確かめていない、Graphiteの完成したグラフ。
pub(super) struct 未検証の地図 {
    つながり: Graph,
}

impl 未検証の地図 {
    pub(super) fn 生成する(つながり: Graph) -> Self {
        Self { つながり }
    }

    /// 4つの不変条件を確かめ、通り口の一覧と一緒に地図にする。最初に見つけた破れを失敗として返す。
    pub(super) fn 検証する(self) -> Result<地点と経路のグラフ, 地図の生成の失敗> {
        self.区域どうしの重なりを確かめる()?;
        let 通り口一覧 = self.つながり.経路_iter().map(|経路| self.経路を確かめる(経路)).collect::<Result<Vec<_>, _>>()?;
        通り口どうしの重なりを確かめる(&通り口一覧)?;
        Ok(地点と経路のグラフ::確かめた部品から作る(self.つながり, 通り口一覧))
    }

    fn 区域どうしの重なりを確かめる(&self) -> Result<(), 地図の生成の失敗> {
        let 地点一覧: Vec<_> = self.つながり.地点_iter().collect();
        for (番号, 一方) in 地点一覧.iter().enumerate() {
            for もう一方 in 地点一覧.iter().skip(番号 + 1) {
                if 一方.value().区域().多角形().内部が重なるか(もう一方.value().区域().多角形()) {
                    return Err(地図の生成の失敗::区域の内部が重なっている {
                        一方の地点: 地点の識別子::確かめた図式の識別子から作る(一方.id().clone()),
                        もう一方の地点: 地点の識別子::確かめた図式の識別子から作る(もう一方.id().clone()),
                    });
                }
            }
        }
        Ok(())
    }

    // 経路1本の両端・種類と予定・通り口を確かめ、確かめた通り口にする。
    fn 経路を確かめる(&self, 経路: 経路Ref<'_>) -> Result<確かめた通り口, 地図の生成の失敗> {
        let 識別子 = 経路の識別子::確かめた図式の識別子から作る(経路.id().clone());
        let (一方, もう一方) = 経路.endpoints();
        if 一方.id() == もう一方.id() {
            return Err(地図の生成の失敗::経路の両端が同じ地点である { 経路: 識別子 });
        }
        let 積み荷 = 経路.積み荷();
        let 閉じる予定を持つ = 積み荷.予定().はじめの開閉() == 経路の開閉::閉じている || 積み荷.予定().時間帯を持つか();
        if !積み荷.種類().封鎖できるか() && 閉じる予定を持つ {
            return Err(地図の生成の失敗::封鎖できない経路が閉じる予定を持つ { 経路: 識別子, 種類: 積み荷.種類() });
        }
        let 当て方 = 通り口の辺の当て方::経路の両端の区域と照らして当てる(経路)?;
        let 開閉の対象 = if 積み荷.種類().封鎖できるか() {
            通り口の開閉の対象::封鎖できる {
                経路: 封鎖できる経路の識別子::確かめた図式の識別子から作る(経路.id().clone()),
            }
        } else {
            通り口の開閉の対象::封鎖できない
        };
        Ok(確かめた通り口 {
            経路: 識別子,
            一方の辺: 区域の辺の所在 {
                地点: 地点の識別子::確かめた図式の識別子から作る(一方.id().clone()),
                辺: 当て方.一方の区域の辺,
            },
            もう一方の辺: 区域の辺の所在 {
                地点: 地点の識別子::確かめた図式の識別子から作る(もう一方.id().clone()),
                辺: 当て方.もう一方の区域の辺,
            },
            開閉の対象,
        })
    }
}
