//! 地点と経路のグラフ(地図)。ステージを作る時点で通れる可能性のある経路を全部置いた、作った後に変わらない地点と経路のつながりである。
//! Graphiteの完成したグラフは構造を変えられないが、節点の値と辺の積み荷を `&mut` で書き換える口(`_value_mut`・`_payload_mut`)を持つ。
//! その口を持つ型は `M不変データ`(自己変更を行わない)になれないため、完成したグラフを私有のフィールドに包み、読み取りの口だけを公開する。
//! これが、Graphiteのグラフと `M不変データ` を両立させる書き方である(Issue #187 の確かめる事項)。
//! 地図は、区域と通り口と経路の種類の不変条件を地図の検証(`地図の検証.rs`)で確かめてからでないと作れない。検証が確かめた通り口の一覧も一緒に持つ。
//! 地点と経路の識別子を作るのは、この型と、この型が並べた経路の図式の識別子を包む開閉の規則と、地図の検証だけである(参照: `識別子.rs` の冒頭)。

use blitz_design::{M不変データ, M値オブジェクト};

use super::区域の形::区域;
use super::図式::地点と経路の図式::{Graph, 地点Id, 経路Id};
use super::地図の失敗::地図の生成の失敗;
use super::地図の検証::未検証の地図;
use super::封鎖できる経路::封鎖できる経路の識別子;
use super::積み荷::経路の積み荷;
use super::識別子::{地点の識別子, 経路の識別子};
use super::通り口::確かめた通り口;
use super::開閉の予定::経路の開閉の予定;

/// 地点と経路のつながりを持つ、作った後に変わらない地図。
#[derive(Clone)]
pub struct 地点と経路のグラフ {
    つながり: Graph,
    通り口一覧: Vec<確かめた通り口>,
}

impl M不変データ for 地点と経路のグラフ {}

/// 経路がつなぐ2つの地点。経路は向きを持たないため、どちらを一方と呼ぶかに意味は無い。
#[derive(Debug, Clone, PartialEq)]
pub struct 経路の両端 {
    pub 一方の地点: 地点の識別子,
    pub もう一方の地点: 地点の識別子,
}

impl M不変データ for 経路の両端 {}
impl M値オブジェクト for 経路の両端 {}

impl 地点と経路のグラフ {
    /// Graphiteの完成したグラフを、区域と通り口と経路の種類の不変条件で確かめて地図にする。多重度と端点の検査はGraphiteの凍結が済ませている。
    pub fn 検証して生成する(つながり: Graph) -> Result<Self, 地図の生成の失敗> {
        未検証の地図::生成する(つながり).検証する()
    }

    /// 地図の検証が確かめた部品から地図を作る。呼ぶのは地図の検証だけである。
    pub(super) fn 確かめた部品から作る(つながり: Graph, 通り口一覧: Vec<確かめた通り口>) -> Self {
        Self { つながり, 通り口一覧 }
    }

    /// 図式の識別子の経路がこの地図に在れば、その経路の識別子を返す。
    pub fn 経路を確かめる(&self, 識別子: &経路Id) -> Option<経路の識別子> {
        self.つながり.経路_by_id(識別子).map(|経路| 経路の識別子::確かめた図式の識別子から作る(経路.id().clone()))
    }

    /// 図式の識別子の地点がこの地図に在れば、その地点の識別子を返す。
    pub fn 地点を確かめる(&self, 識別子: &地点Id) -> Option<地点の識別子> {
        self.つながり.地点_by_id(識別子).map(|地点| 地点の識別子::確かめた図式の識別子から作る(地点.id().clone()))
    }

    /// その経路がこの地図に在り、封鎖できる種類であれば、封鎖できる経路の識別子を返す。封鎖できない経路(脇道・山道)は無しである。
    pub fn 封鎖できる経路として確かめる(&self, 経路: &経路の識別子) -> Option<封鎖できる経路の識別子> {
        let 見つけた = self.つながり.経路_by_id(経路.図式の識別子())?;
        見つけた.積み荷().種類().封鎖できるか().then(|| 封鎖できる経路の識別子::確かめた図式の識別子から作る(見つけた.id().clone()))
    }

    /// その封鎖できる経路の識別子がこの地図の封鎖できる経路を指しているか。別の地図が渡した識別子は、同じ表記の封鎖できる経路がこの地図に無ければ偽になる。
    pub fn 封鎖できる経路を持つか(&self, 経路: &封鎖できる経路の識別子) -> bool {
        self.つながり.経路_by_id(経路.図式の識別子()).is_some_and(|見つけた| 見つけた.積み荷().種類().封鎖できるか())
    }

    /// この地図の経路の識別子を、識別子の順に並べて返す。
    pub fn 経路の識別子一覧(&self) -> Vec<経路の識別子> {
        let mut 一覧: Vec<経路の識別子> = self.つながり.経路_ids().map(|識別子| 経路の識別子::確かめた図式の識別子から作る(識別子.clone())).collect();
        一覧.sort();
        一覧
    }

    /// この地図の地点の識別子を、識別子の順に並べて返す。
    pub fn 地点の識別子一覧(&self) -> Vec<地点の識別子> {
        let mut 一覧: Vec<地点の識別子> = self.つながり.地点_ids().map(|識別子| 地点の識別子::確かめた図式の識別子から作る(識別子.clone())).collect();
        一覧.sort();
        一覧
    }

    /// この地図の封鎖できる経路の識別子を、識別子の順に並べて返す。
    pub fn 封鎖できる経路の識別子一覧(&self) -> Vec<封鎖できる経路の識別子> {
        let mut 一覧: Vec<封鎖できる経路の識別子> = self.封鎖できる経路と予定の一覧().map(|(識別子, _)| 封鎖できる経路の識別子::確かめた図式の識別子から作る(識別子.clone())).collect();
        一覧.sort();
        一覧
    }

    /// その経路がつなぐ2つの地点。経路がこの地図に無ければ無しである。
    pub fn 経路の両端を求める(&self, 経路: &経路の識別子) -> Option<経路の両端> {
        let (一方, もう一方) = self.つながり.経路_by_id(経路.図式の識別子())?.endpoints();
        Some(経路の両端 {
            一方の地点: 地点の識別子::確かめた図式の識別子から作る(一方.id().clone()),
            もう一方の地点: 地点の識別子::確かめた図式の識別子から作る(もう一方.id().clone()),
        })
    }

    /// その経路の積み荷(種類・通り口・開閉の予定)。経路がこの地図に無ければ無しである。
    pub fn 経路の積み荷を読む(&self, 経路: &経路の識別子) -> Option<&経路の積み荷> {
        self.つながり.経路_by_id(経路.図式の識別子()).map(|経路| 経路.積み荷())
    }

    /// その地点の区域。地点がこの地図に無ければ無しである。
    pub fn 地点の区域を読む(&self, 地点: &地点の識別子) -> Option<&区域> {
        self.つながり.地点_by_id(地点.図式の識別子()).map(|見つけた| 見つけた.value().区域())
    }

    /// 地図の検証が確かめた通り口を、経路が地図に並ぶ順に並べる。
    pub fn 通り口一覧(&self) -> &[確かめた通り口] {
        &self.通り口一覧
    }

    /// 封鎖できる経路の図式の識別子と開閉の予定の対を、地図が持つ順に並べる。開閉の規則が刻みごとに時刻の予定を読むための口である。
    /// 封鎖できない経路は閉じる予定を持たないことを地図の検証が確かめているため、並べない。
    /// 刻みごとに呼ばれるため、変化の無い経路の識別子を作らないよう、図式の識別子のまま渡す。
    pub(super) fn 封鎖できる経路と予定の一覧(&self) -> impl Iterator<Item = (&経路Id, &経路の開閉の予定)> {
        self.つながり.経路_iter().filter(|経路| 経路.積み荷().種類().封鎖できるか()).map(|経路| (経路.id(), 経路.積み荷().予定()))
    }
}
