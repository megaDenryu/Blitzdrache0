//! 経路が時間によって閉じている時間帯。始まりの時刻に経路が閉じ、終わりの時刻に経路が開くという、ステージを作る人が経路へ置く予定の1件を表す。
//! 始まりが終わりより前であることを不変条件に持ち、公開フィールドの指定を検証して初めて得られる(`移動可能範囲の指定` と同じ様式)。
//! 始まりと終わりを同じ型の2引数で受けないのは、取り違えても型が通るためである。

use blitz_design::{M不変データ, M値オブジェクト};

use crate::時刻::世界の時刻;

/// 閉じている時間帯を作るための指定。検証を通ると閉じている時間帯になる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 閉じている時間帯の指定 {
    pub 始まり: 世界の時刻,
    pub 終わり: 世界の時刻,
}

impl M不変データ for 閉じている時間帯の指定 {}

impl 閉じている時間帯の指定 {
    /// 始まりが終わりより前であることを確かめて閉じている時間帯を作る。長さ0の時間帯は、閉じてすぐ開く予定であり何も表さないため拒む。
    pub fn 検証する(self) -> Result<閉じている時間帯, 閉じている時間帯の生成の失敗> {
        if self.始まり >= self.終わり {
            return Err(閉じている時間帯の生成の失敗::始まりが終わりより前でない {
                始まり: self.始まり, 終わり: self.終わり
            });
        }
        Ok(閉じている時間帯 {
            始まり: self.始まり, 終わり: self.終わり
        })
    }
}

/// 経路が閉じている時間帯。始まりの時刻を含み、終わりの時刻を含まない。始まりは終わりより前である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 閉じている時間帯 {
    始まり: 世界の時刻,
    終わり: 世界の時刻,
}

impl M不変データ for 閉じている時間帯 {}
impl M値オブジェクト for 閉じている時間帯 {}

impl 閉じている時間帯 {
    pub fn 始まり(&self) -> 世界の時刻 {
        self.始まり
    }

    pub fn 終わり(&self) -> 世界の時刻 {
        self.終わり
    }
}

/// 閉じている時間帯の指定が不変条件を満たさなかった理由。
#[derive(Debug, Clone, Copy, PartialEq, thiserror::Error)]
pub enum 閉じている時間帯の生成の失敗 {
    #[error("閉じている時間帯の始まり{始まり:?}が終わり{終わり:?}より前でない(始まりは終わりより前でなければならない)")]
    始まりが終わりより前でない { 始まり: 世界の時刻, 終わり: 世界の時刻 },
}
