//! 通り口。経路が区域の境目を越えられる箇所であり、経路の両端の2つの地点の区域が共有する1本の辺で指す。
//! 通り口を自由な座標で持たないのは、通り口が境目の上にあることと、両方の区域が同じ辺を持つことを、区域の頂点の番号で確かめられるようにするためである。
//! 辺は始まりの頂点の番号で指す。区域の頂点は反時計回りに並ぶため、2つの区域が共有する辺は、片方では頂点iから頂点i+1へ、もう片方ではその逆向きへ張る。
//! 指定の2つの番号がどちらの区域の辺かは、地図の検証が両端の区域と照らして決める。Graphiteの向きの無い辺は両端の順序を保たないためである。

use blitz_design::{M不変データ, M値オブジェクト};

use super::封鎖できる経路::封鎖できる経路の識別子;
use super::識別子::{地点の識別子, 経路の識別子};

/// 区域の辺を指す、始まりの頂点の番号。辺はその頂点から次の頂点(最後の頂点なら最初の頂点)へ張る。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct 区域の辺の番号(usize);

impl M不変データ for 区域の辺の番号 {}
impl M値オブジェクト for 区域の辺の番号 {}

impl 区域の辺の番号 {
    pub const fn 生成する(始まりの頂点の番号: usize) -> Self {
        Self(始まりの頂点の番号)
    }

    pub fn 始まりの頂点の番号(&self) -> usize {
        self.0
    }
}

/// 経路の通り口の指定。経路の両端の区域それぞれの辺の番号を1つずつ持つ。どちらの番号がどちらの区域の辺かは問わない。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 通り口の指定 {
    pub 片方の区域の辺: 区域の辺の番号,
    pub もう片方の区域の辺: 区域の辺の番号,
}

impl M不変データ for 通り口の指定 {}
impl M値オブジェクト for 通り口の指定 {}

/// ある地点の区域の、ある辺。地図が確かめた後の通り口の片側を表す。
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct 区域の辺の所在 {
    pub 地点: 地点の識別子,
    pub 辺: 区域の辺の番号,
}

impl M不変データ for 区域の辺の所在 {}
impl M値オブジェクト for 区域の辺の所在 {}

/// 通り口を開け閉めできるか。封鎖できない経路の通り口はいつも開いており、封鎖できる経路の通り口は経路の開閉の状態に従う。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 通り口の開閉の対象 {
    封鎖できない,
    封鎖できる { 経路: 封鎖できる経路の識別子 },
}

impl M不変データ for 通り口の開閉の対象 {}
impl M値オブジェクト for 通り口の開閉の対象 {}

/// 地図が検証した通り口。経路と、その両端の区域の辺と、開け閉めできるかを持つ。
/// フィールドを `地点と経路` の中へだけ開くのは、両端の区域の辺を照らした地図の検証だけがこの値を組むためである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 確かめた通り口 {
    pub(super) 経路: 経路の識別子,
    pub(super) 一方の辺: 区域の辺の所在,
    pub(super) もう一方の辺: 区域の辺の所在,
    pub(super) 開閉の対象: 通り口の開閉の対象,
}

impl M不変データ for 確かめた通り口 {}
impl M値オブジェクト for 確かめた通り口 {}

impl 確かめた通り口 {
    pub fn 経路(&self) -> &経路の識別子 {
        &self.経路
    }

    pub fn 開閉の対象(&self) -> &通り口の開閉の対象 {
        &self.開閉の対象
    }

    /// 通り口の2つの側を、一方・もう一方の順に並べる。
    pub fn 両側(&self) -> [&区域の辺の所在; 2] {
        [&self.一方の辺, &self.もう一方の辺]
    }

    /// その辺から通り口を抜けた先の地点。その辺がこの通り口の片側でなければ無しである。
    pub fn その辺から抜けた先(&self, 辺: &区域の辺の所在) -> Option<&地点の識別子> {
        if &self.一方の辺 == 辺 {
            Some(&self.もう一方の辺.地点)
        } else if &self.もう一方の辺 == 辺 {
            Some(&self.一方の辺.地点)
        } else {
            None
        }
    }
}
