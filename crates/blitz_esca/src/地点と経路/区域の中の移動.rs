//! 区域の中の移動。地点の区域の中の始点から終点へ動こうとしたとき、区域の境目で何が起きるかを決める工程である(2026-09-26 オーナー裁定)。
//! 切り出しの根拠は、呼び出し連鎖の中の独立した工程である(CLAUDE.md「切り出しの根拠義務」の5号)。受け取るのは空間制約と移動の指定、返すのは移動の結果である。
//! 入口は `区域の空間制約::区域の中で動かす`(`空間制約.rs`)であり、ここは移動の途中の状態(`移動の途中`)と、それを一区切りずつ進める手順を持つ。
//!
//! 動きが区域の閉包から初めて外へ出る位置(出口)で、次の順に決める。
//! 1. 出口がいま開いている通り口の辺の上にあり、出口から先の動きが通り口の向こうの区域の閉包に入るなら、その区域へ入り、残りの動きをそこで続ける。
//! 2. そうでなければ境目に遮られる。出口が辺の途中なら、残りの動きをその辺に沿わせて1回だけ滑る(長方形の範囲の端で滑るのと同じ感触)。
//!    滑った動きがさらに境目に遮られるか、出口が区域の角(頂点)にあれば、そこで止まる。1刻みに滑るのを1回に限るのは、角で動きが往復しないためである。
//!
//! 境目の上の点は、その境目を持つどちらの区域の閉包にも入るが、旅行者がどちらにいるかは点でなく移動の結果の地点が決める。
//! 閉じた通り口の上に立った旅行者は、来た側の区域にいるまま、向こう側へは閉じた境目として遮られる。
//! 1刻みの通り口の通過は、開いている通り口の数まで起こりうる。繰り返しの上限はそれに滑りと着く分を足した数であり、上限に達したら、いる区域の中の今の点で止まる。

use super::区域の中の移動の型::{区域の中の移動の失敗, 区域の中の移動の指定, 区域の中の移動の結果};
use super::空間制約::区域の空間制約;
use super::識別子::地点の識別子;
use crate::平面の幾何::多角形::単純多角形;
use crate::平面の幾何::点と線分::{平面の点, 平面の線分};

/// 移動の途中の状態。いる地点・今の始点・目指す終点と、これまでに遮られたか・滑ったかを持つ。
pub(super) struct 移動の途中 {
    地点: 地点の識別子,
    始点: 平面の点,
    終点: 平面の点,
    遮られた: bool,
    滑った: bool,
}

// 一区切り進めた後の次の手。
enum 移動の進み方 {
    着いた(区域の中の移動の結果),
    続ける(移動の途中),
}

impl 移動の途中 {
    /// 始点がいる地点の区域の閉包にあることを確かめて移動を始める。
    pub(super) fn 始める(制約: &区域の空間制約, 指定: 区域の中の移動の指定) -> Result<Self, 区域の中の移動の失敗> {
        if !制約.地点の多角形(&指定.地点)?.閉包に入るか(&指定.始点) {
            return Err(区域の中の移動の失敗::始点が地点の区域の外にある { 地点: 指定.地点, 始点: 指定.始点 });
        }
        Ok(Self {
            地点: 指定.地点,
            始点: 指定.始点,
            終点: 指定.終点,
            遮られた: false,
            滑った: false,
        })
    }

    /// 着くまで一区切りずつ進める。繰り返しの上限は、開いている通り口の数に、滑りと着く分を足した数である。
    pub(super) fn 着くまで進める(self, 制約: &区域の空間制約) -> Result<区域の中の移動の結果, 区域の中の移動の失敗> {
        let mut 途中 = self;
        for _ in 0..制約.通れる通り口().通り口一覧().len() + 3 {
            match 途中.一区切り進める(制約)? {
                移動の進み方::着いた(結果) => return Ok(結果),
                移動の進み方::続ける(次の途中) => 途中 = 次の途中,
            }
        }
        Ok(途中.いまの点で止める())
    }

    // 今の始点から終点へ向かい、出口まで進めて、通り口を抜けるか、滑るか、止まるかを決める。
    fn 一区切り進める(self, 制約: &区域の空間制約) -> Result<移動の進み方, 区域の中の移動の失敗> {
        let 多角形 = 制約.地点の多角形(&self.地点)?;
        let 線分 = 平面の線分 { 始点: self.始点, 終点: self.終点 };
        let Some(出る位置) = 多角形.線分が初めて外へ出る媒介変数(&線分) else {
            let 終点 = self.終点;
            return Ok(移動の進み方::着いた(self.その点で着く(終点)));
        };
        let 出口 = 線分.媒介変数の点(出る位置);
        let 残り = 平面の線分 { 始点: 出口, 終点: self.終点 };
        if let Some(先) = self.通り口を抜けた先(制約, 多角形, &残り) {
            return Ok(移動の進み方::続ける(Self { 地点: 先, 始点: 出口, ..self }));
        }
        let 沿わせた終点 = if self.滑った { None } else { 多角形.境界に沿わせた終点(&出口, &self.終点) };
        Ok(match 沿わせた終点 {
            Some(終点) => 移動の進み方::続ける(Self {
                始点: 出口,
                終点,
                遮られた: true,
                滑った: true,
                ..self
            }),
            None => 移動の進み方::着いた(Self { 遮られた: true, ..self }.その点で着く(出口)),
        })
    }

    fn その点で着く(self, 到達点: 平面の点) -> 区域の中の移動の結果 {
        区域の中の移動の結果 {
            地点: self.地点,
            到達点,
            遮られた: self.遮られた,
        }
    }

    // 繰り返しの上限に達したとき、いる区域の閉包の中の今の始点で止める。
    fn いまの点で止める(self) -> 区域の中の移動の結果 {
        let 始点 = self.始点;
        Self { 遮られた: true, ..self }.その点で着く(始点)
    }

    // 出口がいる地点の開いている通り口の辺の上にあり、出口から先の動き(残り)が向こうの区域の閉包に入るなら、向こうの地点。
    fn 通り口を抜けた先(&self, 制約: &区域の空間制約, 多角形: &単純多角形, 残り: &平面の線分) -> Option<地点の識別子> {
        let 出口 = 残り.始点;
        制約.通れる通り口().通り口一覧().iter().flat_map(|通り口| 通り口.両側().map(|側| (通り口, 側))).find_map(|(通り口, 側)| {
            if 側.地点 != self.地点 || 多角形.辺(側.辺.始まりの頂点の番号())?.点までの距離(&出口) > 出口.境界の許容幅() {
                return None;
            }
            let 先 = 通り口.その辺から抜けた先(側)?;
            制約.地図().地点の区域を読む(先)?.多角形().線分の始めの区間が閉包に入るか(残り).then(|| 先.clone())
        })
    }
}
