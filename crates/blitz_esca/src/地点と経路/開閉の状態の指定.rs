//! 経路の開閉の状態を作るための指定。閉じている経路と出来事が触れた経路の2つの並びを、私有のフィールドで持つ。
//! 状態へは `経路の開閉の規則::指定を地図で確かめて状態を作る` だけが変える。2つの並びを同じ型の2引数で受けず、名前の違う2つの口で1つずつ受けるのは、取り違えても型が通るためである。
//! 出来事が触れた経路も受け取るのは、保存からの復元のように途中の状態を作り直すとき、出来事が予定に勝つという裁定の効果を黙って消さないためである。

use blitz_design::{MParameter, M不変データ, M値オブジェクト};

use super::封鎖できる経路::封鎖できる経路の識別子;

/// 経路の開閉の状態を作るための指定。検証は規則が自分の地図で行う。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 経路の開閉の状態の指定 {
    閉じている経路: Vec<封鎖できる経路の識別子>,
    出来事が触れた経路: Vec<封鎖できる経路の識別子>,
}

impl M不変データ for 経路の開閉の状態の指定 {}
impl MParameter for 経路の開閉の状態の指定 {}
impl M値オブジェクト for 経路の開閉の状態の指定 {}

impl 経路の開閉の状態の指定 {
    /// 閉じている経路を持ち、出来事が触れた経路を持たない指定。
    pub fn 閉じている経路から生成する(閉じている経路: Vec<封鎖できる経路の識別子>) -> Self {
        Self {
            閉じている経路,
            出来事が触れた経路: Vec::new(),
        }
    }

    /// 出来事が触れた経路を置き換えた指定。
    pub fn 出来事が触れた経路を置き換えた指定(self, 出来事が触れた経路: Vec<封鎖できる経路の識別子>) -> Self {
        Self { 出来事が触れた経路, ..self }
    }

    pub fn 閉じている経路(&self) -> &[封鎖できる経路の識別子] {
        &self.閉じている経路
    }

    pub fn 出来事が触れた経路(&self) -> &[封鎖できる経路の識別子] {
        &self.出来事が触れた経路
    }

    /// 指定を消費して、2つの並びを複製せずに移す。規則が地図で確かめた後に、状態が自分の集合へ移すために使う。
    pub(super) fn 経路の並びを取り出す(self) -> 指定から取り出した経路の並び {
        指定から取り出した経路の並び {
            閉じている経路: self.閉じている経路,
            出来事が触れた経路: self.出来事が触れた経路,
        }
    }
}

/// 状態の指定を消費して取り出した2つの並び。`地点と経路` の外へ出さない受け渡しの値であり、2つの並びを名前で区別して取り違えを防ぐ。
pub(super) struct 指定から取り出した経路の並び {
    pub(super) 閉じている経路: Vec<封鎖できる経路の識別子>,
    pub(super) 出来事が触れた経路: Vec<封鎖できる経路の識別子>,
}
