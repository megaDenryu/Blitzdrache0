//! 経路の種類。ステージを作る人が経路1本ごとに選ぶ、その経路が何であるか(幹線道路・橋・門・脇道・山道)の区別である。
//! 種類は、その経路を封鎖できるかを決める(2026-09-26 オーナー裁定)。幹線道路・橋・門は封鎖でき、脇道・山道は封鎖できない。
//! 時間や危険などの種類ごとの性質は第3段階で決めるため、ここは封鎖できるかだけを答える。
//! 壁が壊れて通れるようになる抜け道は、はじめは閉じた門として置く。

use blitz_design::{M不変データ, M値オブジェクト};

/// 経路1本が何であるか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 経路の種類 {
    幹線道路,
    橋,
    門,
    脇道,
    山道,
}

impl M不変データ for 経路の種類 {}
impl M値オブジェクト for 経路の種類 {}

impl 経路の種類 {
    /// この種類の経路を封鎖できるか。封鎖できない経路は、はじめから閉じていることも時刻の予定を持つことも無く、開閉の命令の対象にもならない。
    pub fn 封鎖できるか(&self) -> bool {
        match self {
            Self::幹線道路 | Self::橋 | Self::門 => true,
            Self::脇道 | Self::山道 => false,
        }
    }
}
