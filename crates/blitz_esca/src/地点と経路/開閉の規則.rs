//! 経路の開閉の規則。開閉の遷移へ読み取り専用で与える、地図(地点と経路のグラフ)である。
//! 規則は、経路の開閉の状態を作る口(はじめの状態と、状態の指定を地図で確かめて作る状態)と、状態と命令が指す経路が地図に在るかを確かめる口と、
//! 遷移パラメータの刻みに来た時刻の予定から経路の開閉の変化を求める口を持つ。状態を作る口を規則だけが持つのは、状態の経路をその状態を遷移させる地図で確かめるためである。
//! 時刻の予定は地図の辺の積み荷(経路の開閉の予定)にあるため、規則が持つ値は地図1つである。地図そのものに `M規則` を付けないのは、
//! 地図は開閉の遷移のほかに歩行の側(第2段階の区域との接続)からも読まれる `M不変データ` であり、開閉の遷移の規則はその読み方の1つだからである。

use blitz_design::{M不変データ, M規則};

use super::地図::地点と経路のグラフ;
use super::指定の失敗::経路の指定の失敗;
use super::識別子::経路の識別子;
use super::開閉の予定::経路の開閉;
use super::開閉の命令::経路の開閉の命令;
use super::開閉の状態::経路の開閉の状態;
use super::開閉の状態の指定::経路の開閉の状態の指定;
use crate::transition_parameter::遷移パラメータ;

/// 開閉の遷移の規則。
#[derive(Clone)]
pub struct 経路の開閉の規則 {
    地図: 地点と経路のグラフ,
}

impl M不変データ for 経路の開閉の規則 {}
impl M規則 for 経路の開閉の規則 {}

/// 経路1本の開閉を、どちらへ変えるかの1件。時刻の予定と命令の両方がこの形で変化を出す。遷移は、出来事が触れた経路への時刻の予定の変化を捨ててから当てる。
#[derive(Debug, Clone, PartialEq)]
pub(super) struct 経路の開閉の変化 {
    pub(super) 経路: 経路の識別子,
    pub(super) 変わる先: 経路の開閉,
}

impl M不変データ for 経路の開閉の変化 {}

impl 経路の開閉の規則 {
    pub fn 生成する(地図: 地点と経路のグラフ) -> Self {
        Self { 地図 }
    }

    pub fn 地図(&self) -> &地点と経路のグラフ {
        &self.地図
    }

    /// 地図の経路の開閉の予定のうち、はじめに閉じている経路だけを閉じている状態。
    pub fn はじめの状態(&self) -> 経路の開閉の状態 {
        let 閉じている経路 = self
            .地図
            .経路の識別子一覧()
            .into_iter()
            .filter(|経路| self.地図.経路の開閉の予定を読む(経路).is_some_and(|予定| 予定.はじめの開閉() == 経路の開閉::閉じている))
            .collect();
        経路の開閉の状態::確かめた指定から作る(経路の開閉の状態の指定 {
            閉じている経路,
            出来事が触れた経路: Vec::new(),
        })
    }

    /// 指定の閉じている経路と出来事が触れた経路が、どれもこの規則の地図に在ることを確かめて状態を作る。
    pub fn 指定を地図で確かめて状態を作る(&self, 指定: 経路の開閉の状態の指定) -> Result<経路の開閉の状態, 経路の指定の失敗> {
        self.どの経路も地図に在ることを確かめる(指定.閉じている経路.iter().chain(指定.出来事が触れた経路.iter()))?;
        Ok(経路の開閉の状態::確かめた指定から作る(指定))
    }

    /// 状態の閉じている経路と出来事が触れた経路と命令が指す経路が、どれもこの規則の地図に在ることを確かめる。命令が無ければ状態の経路だけを確かめる。
    pub(super) fn 状態と命令が指す経路を確かめる(&self, 状態: &経路の開閉の状態, 命令: &経路の開閉の命令) -> Result<(), 経路の指定の失敗> {
        self.どの経路も地図に在ることを確かめる(状態.閉じている経路一覧().chain(状態.出来事が触れた経路一覧()).chain(命令.指す経路()))
    }

    // 並びの経路がどれも地図に在ることを確かめる。地図に無い経路があれば、最初の1本を失敗の理由にする。
    fn どの経路も地図に在ることを確かめる<'a>(&self, mut 経路一覧: impl Iterator<Item = &'a 経路の識別子>) -> Result<(), 経路の指定の失敗> {
        match 経路一覧.find(|経路| !self.地図.経路を持つか(経路)) {
            Some(経路) => Err(経路の指定の失敗::地図に無い経路を指した { 経路: 経路.clone() }),
            None => Ok(()),
        }
    }

    /// 遷移パラメータの刻みに来た時刻の予定が起こす変化を、同じ経路の中では時刻の順に並べて返す。
    /// 経路どうしの順は結果に効かない(経路1本の変化は他の経路の開閉を読まない)ため、地図が経路を並べる順のままにする。
    /// 刻みごとに呼ばれるため、経路を並べ替えず、変化の無い経路については識別子を作らない。
    pub(super) fn この刻みに時刻が起こす変化一覧(&self, パラメータ: 遷移パラメータ) -> Vec<経路の開閉の変化> {
        let mut 変化一覧 = Vec::new();
        for (図式の識別子, 予定) in self.地図.経路と予定の一覧() {
            for 変わる先 in 予定.この刻みに来る変化一覧(パラメータ) {
                変化一覧.push(経路の開閉の変化 {
                    経路: 経路の識別子::確かめた図式の識別子から作る(図式の識別子.clone()),
                    変わる先,
                });
            }
        }
        変化一覧
    }
}
