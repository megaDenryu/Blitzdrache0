//! 経路の開閉の規則。開閉の遷移へ読み取り専用で与える、地図(地点と経路のグラフ)である。
//! 規則は、命令が指す経路が地図に在るかを確かめる口と、遷移パラメータの刻みに来た時刻の予定から経路の開閉の変化を求める口を持つ。
//! 時刻の予定は地図の辺の積み荷(経路の開閉の予定)にあるため、規則が持つ値は地図1つである。地図そのものに `M規則` を付けないのは、
//! 地図は開閉の遷移のほかに歩行の側(第2段階の区域との接続)からも読まれる `M不変データ` であり、開閉の遷移の規則はその読み方の1つだからである。

use blitz_design::{M不変データ, M規則};

use super::地図::地点と経路のグラフ;
use super::指定の失敗::経路の指定の失敗;
use super::識別子::経路の識別子;
use super::開閉の予定::経路の開閉;
use super::開閉の命令::経路の開閉の命令;
use crate::transition_parameter::遷移パラメータ;

/// 開閉の遷移の規則。
#[derive(Clone)]
pub struct 経路の開閉の規則 {
    地図: 地点と経路のグラフ,
}

impl M不変データ for 経路の開閉の規則 {}
impl M規則 for 経路の開閉の規則 {}

/// 経路1本の開閉を、どちらへ変えるかの1件。時刻の予定と命令の両方がこの形で変化を出し、遷移が出た順に当てる。
#[derive(Debug, Clone, PartialEq)]
pub(super) struct 経路の開閉の変化 {
    pub(super) 経路: 経路の識別子,
    pub(super) 変わる先: 経路の開閉,
}

impl M不変データ for 経路の開閉の変化 {}

impl 経路の開閉の規則 {
    pub fn 生成する(地図: 地点と経路のグラフ) -> Self {
        Self { 地図 }
    }

    pub fn 地図(&self) -> &地点と経路のグラフ {
        &self.地図
    }

    /// 命令が指す経路がこの規則の地図に在ることを確かめる。命令が無ければ確かめるものは無い。
    pub(super) fn 命令の経路を確かめる(&self, 命令: &経路の開閉の命令) -> Result<(), 経路の指定の失敗> {
        match 命令.指す経路() {
            Some(経路) if !self.地図.経路を持つか(経路) => Err(経路の指定の失敗::地図に無い経路を指した { 経路: 経路.clone() }),
            Some(_) | None => Ok(()),
        }
    }

    /// 遷移パラメータの刻みに来た時刻の予定が起こす変化を、同じ経路の中では時刻の順に並べて返す。
    /// 経路どうしの順は結果に効かない(経路1本の変化は他の経路の開閉を読まない)ため、地図が経路を並べる順のままにする。
    /// 刻みごとに呼ばれるため、経路を並べ替えず、変化の無い経路については識別子を作らない。
    pub(super) fn この刻みに時刻が起こす変化一覧(&self, パラメータ: 遷移パラメータ) -> Vec<経路の開閉の変化> {
        let mut 変化一覧 = Vec::new();
        for (図式の識別子, 予定) in self.地図.経路と予定の一覧() {
            for 変わる先 in 予定.この刻みに来る変化一覧(パラメータ) {
                変化一覧.push(経路の開閉の変化 {
                    経路: 経路の識別子::確かめた図式の識別子から作る(図式の識別子.clone()),
                    変わる先,
                });
            }
        }
        変化一覧
    }
}
