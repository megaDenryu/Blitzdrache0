//! 経路の開閉の状態と、その開閉の遷移。閉じている経路の識別子の集合を持つ `M状態` であり、旅行者が経路を通れるかどうかの正本である。
//! 集合を識別子の順に並ぶ集合で持つのは、出来事の並びと状態の比較と表記が、経路を加えた順に左右されないためである。
//!
//! 遷移は状態を値で受け取り、失敗しうる検査(命令が指す経路が規則の地図に在るか)を集合を動かす前に全部済ませる(設計オントロジー 2.5.3)。
//! 変化は、刻みに来た時刻の予定の変化を先に、命令の変化を後に当てる。同じ刻みで時刻が閉じた経路を命令が開けば、経路は開いたまま残る。
//! 命令を後にするのは、命令が出来事への反応として世界の事実から作られた意志であり、時刻の予定は何も起きなかったときの既定の流れだからである
//! (参照: `_doc/設計/Esca/設計正本.md` 5節)。出来事は、変化が触れた経路ごとに遷移の前後の開閉の差から組む(法則E2)。

use std::collections::{BTreeMap, BTreeSet};

use blitz_design::{M不変データ, M状態};

use super::地図::地点と経路のグラフ;
use super::指定の失敗::経路の指定の失敗;
use super::識別子::経路の識別子;
use super::開閉の予定::経路の開閉;
use super::開閉の出来事::経路の開閉の出来事;
use super::開閉の命令::経路の開閉の命令;
use super::開閉の規則::経路の開閉の規則;
use crate::ontology::{M遷移関数, 遷移失敗結果, 遷移成功結果};
use crate::transition_parameter::遷移パラメータ;

/// 閉じている経路の集合。集合に無い地図の経路は開いている。フィールドは私有であり、地図で確かめる口を通らずには作れない。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct 経路の開閉の状態 {
    閉じている経路: BTreeSet<経路の識別子>,
}

impl M不変データ for 経路の開閉の状態 {}
impl M状態 for 経路の開閉の状態 {}

impl 経路の開閉の状態 {
    /// 地図の経路の開閉の予定のうち、はじめに閉じている経路だけを閉じている状態。
    pub fn 地図のはじめの状態(地図: &地点と経路のグラフ) -> Self {
        let 閉じている経路 = 地図
            .経路の識別子一覧()
            .into_iter()
            .filter(|経路| 地図.経路の開閉の予定を読む(経路).is_some_and(|予定| 予定.はじめの開閉() == 経路の開閉::閉じている))
            .collect();
        Self { 閉じている経路 }
    }

    /// 閉じている経路がどれも地図に在ることを確かめて状態を作る。
    pub fn 生成する(地図: &地点と経路のグラフ, 閉じている経路一覧: Vec<経路の識別子>) -> Result<Self, 経路の指定の失敗> {
        if let Some(経路) = 閉じている経路一覧.iter().find(|経路| !地図.経路を持つか(経路)) {
            return Err(経路の指定の失敗::地図に無い経路を指した { 経路: 経路.clone() });
        }
        Ok(Self {
            閉じている経路: 閉じている経路一覧.into_iter().collect(),
        })
    }

    /// その経路がこの状態で開いているか閉じているか。
    pub fn 経路の開閉(&self, 経路: &経路の識別子) -> 経路の開閉 {
        if self.閉じている経路.contains(経路) { 経路の開閉::閉じている } else { 経路の開閉::開いている }
    }

    /// 閉じている経路を識別子の順に並べる。
    pub fn 閉じている経路一覧(&self) -> impl Iterator<Item = &経路の識別子> {
        self.閉じている経路.iter()
    }

    /// 状態を値で受け取り、命令と規則と遷移パラメータ(刻みの始まりの時刻と経過時間)から次の状態と出来事を導く純粋計算(M遷移関数の型シグネチャを満たす)。
    /// 命令が規則の地図に無い経路を指していれば、受け取った状態をそのまま遷移失敗結果にして返す。
    pub fn 開閉を遷移する(
        self,
        命令: &経路の開閉の命令,
        規則: &経路の開閉の規則,
        パラメータ: 遷移パラメータ,
    ) -> Result<遷移成功結果<経路の開閉の状態, 経路の開閉の出来事>, 遷移失敗結果<経路の開閉の状態, 経路の指定の失敗>> {
        if let Err(失敗の理由) = 規則.命令の経路を確かめる(命令) {
            return Err(遷移失敗結果 { 元の状態: self, 失敗の理由 });
        }
        let mut 変化一覧 = 規則.この刻みに時刻が起こす変化一覧(パラメータ);
        変化一覧.extend(命令.開閉の変化());
        let mut 触れた経路の前の開閉 = BTreeMap::new();
        for 変化 in &変化一覧 {
            触れた経路の前の開閉.entry(変化.経路.clone()).or_insert_with(|| self.経路の開閉(&変化.経路));
        }
        let mut 閉じている経路 = self.閉じている経路;
        for 変化 in 変化一覧 {
            match 変化.変わる先 {
                経路の開閉::閉じている => 閉じている経路.insert(変化.経路),
                経路の開閉::開いている => 閉じている経路.remove(&変化.経路),
            };
        }
        let 次の状態 = Self { 閉じている経路 };
        let 出来事一覧 = 触れた経路の前の開閉.into_iter().filter_map(|(経路, 前)| {
            let 後 = 次の状態.経路の開閉(&経路);
            経路の開閉の出来事::前後の開閉の差から組む(経路, 前, 後)
        });
        let 出来事一覧 = 出来事一覧.collect();
        Ok(遷移成功結果 { 次の状態, 出来事一覧 })
    }
}

