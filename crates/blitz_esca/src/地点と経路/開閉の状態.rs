//! 経路の開閉の状態と、その開閉の状態遷移。閉じている封鎖できる経路の識別子の集合と、出来事が触れた封鎖できる経路の識別子の集合を持つ `M状態` であり、旅行者が経路を通れるかどうかの正本である。
//! 出来事が触れた経路とは、開閉の命令(出来事から作られる)が一度でも閉じたり開けたりした経路のことである。
//! 2つの集合を識別子の順に並ぶ集合で持つのは、出来事の並びと状態の比較と表記が、経路を加えた順に左右されないためである。
//!
//! 状態を作る口は規則(`経路の開閉の規則::はじめの状態`・`経路の開閉の規則::指定を地図で確かめて状態を作る`)だけが持ち、この型は地図を外から受け取って状態を作る口を持たない。
//! 地図を外から受ける口を持つと、別の地図で確かめた状態を作れてしまうためである。
//! 状態遷移は状態を値で受け取り、受け取った状態の2つの集合の経路と命令が指す経路が、どれも規則の地図に在るかを、集合を動かす前に確かめる。
//! 地図に無い経路は、ゲームの規則として起きることではなく、別の地図の状態や命令を渡したプログラムの誤りでしか起きないため、状態遷移は失敗を返さずに停止する(2026-09-28 オーナー裁定。設計オントロジー 3.5.9)。
//! 状態の経路も確かめるのは、別の規則から作った状態を渡されたとき、地図の外の経路を持ったまま状態遷移を進めないためである。
//! 時刻の予定と命令が同じ経路にぶつかったときは命令(出来事)が勝つ(2026-09-26 オーナー裁定)。出来事が触れた経路には、それ以降、時刻の予定を当てない。
//! その経路の開閉を変えられるのは別の命令だけである。同じ刻みで時刻の予定と命令が重なったときも、命令が指す経路には予定を当てない。
//! 時刻の予定は、出来事が一度も触れていない経路にだけ当たる(参照: `_doc/設計/Esca/設計正本.md` 5節)。
//! 出来事は、変化が触れた経路ごとに状態遷移の前後の開閉の差から組む(法則E2)。

