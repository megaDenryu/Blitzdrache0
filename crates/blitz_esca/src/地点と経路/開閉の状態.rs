/// 閉じている経路の集合。集合に無い地図の経路は開いている。フィールドは私有であり、規則が地図で確かめる口を通らずには作れない。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct 経路の開閉の状態 {
    閉じている経路: BTreeSet<封鎖できる経路の識別子>,
    出来事が触れた経路: BTreeSet<封鎖できる経路の識別子>,
}

impl M不変データ for 経路の開閉の状態 {}
impl M状態 for 経路の開閉の状態 {}

impl 経路の開閉の状態 {
    /// 規則が地図で確かめた指定の、閉じている経路と出来事が触れた経路をそれぞれ集合にして状態を作る。
    /// 可視性は `地点と経路` の子のモジュール全部へ開いているが、呼ぶのは規則のモジュールだけである。
    pub(super) fn 確かめた指定から作る(指定: 経路の開閉の状態の指定) -> Self {
        Self {
            閉じている経路: 指定.閉じている経路.into_iter().collect(),
            出来事が触れた経路: 指定.出来事が触れた経路.into_iter().collect(),
        }
    }

    /// その経路がこの状態で開いているか閉じているか。
    pub fn 経路の開閉(&self, 経路: &封鎖できる経路の識別子) -> 経路の開閉 {
        if self.閉じている経路.contains(経路) { 経路の開閉::閉じている } else { 経路の開閉::開いている }
    }

    /// 閉じている経路を識別子の順に並べる。
    pub fn 閉じている経路一覧(&self) -> impl Iterator<Item = &封鎖できる経路の識別子> {
        self.閉じている経路.iter()
    }

    /// 出来事(開閉の命令)が一度でも閉じたり開けたりした経路を識別子の順に並べる。これらの経路には時刻の予定が当たらない。
    pub fn 出来事が触れた経路一覧(&self) -> impl Iterator<Item = &封鎖できる経路の識別子> {
        self.出来事が触れた経路.iter()
    }

    /// この状態の閉じている経路と出来事が触れた経路が、どれも地図の封鎖できる経路であることを確かめる。地図に無い経路があれば、最初の1本を失敗の理由にする。
    pub(super) fn 経路がどれも地図に在ることを確かめる(&self, 地図: &地点と経路のグラフ) -> Result<(), 経路の指定の失敗> {
        match self.閉じている経路.iter().chain(self.出来事が触れた経路.iter()).find(|経路| !地図.封鎖できる経路を持つか(経路)) {
            Some(経路) => Err(経路の指定の失敗::地図に無い経路を指した { 経路: 経路.clone() }),
            None => Ok(()),
        }
    }

    /// この状態でいま通れる通り口の集合を、地図が確かめた通り口から導く。封鎖できない経路の通り口はいつも通れ、封鎖できる経路の通り口は閉じていなければ通れる。
    /// 歩行の規則が空間制約として受け取る読み取り専用の値であり、開閉が変わった刻みだけ導き直せばよい(`経路の開閉と旅行者の歩行.rs`)。
    /// 状態の経路が地図に無ければ失敗する。別の地図の状態から導くと、閉じている門を開いていると判断するためである(開閉の遷移が状態の経路を確かめるのと同じ規律)。
    pub fn 通れる通り口を導く(&self, 地図: &地点と経路のグラフ) -> Result<通れる通り口の集合, 経路の指定の失敗> {
        self.経路がどれも地図に在ることを確かめる(地図)?;
        let 開いた通り口一覧 = 地図.通り口一覧().iter().filter(|通り口| match 通り口.開閉の対象() {
            通り口の開閉の対象::封鎖できない => true,
            通り口の開閉の対象::封鎖できる { 経路 } => !self.閉じている経路.contains(経路),
        });
        Ok(通れる通り口の集合::開いた通り口から作る(開いた通り口一覧.cloned().collect()))
    }

    /// 状態を値で受け取り、命令と規則と遷移パラメータ(刻みの始まりの時刻と経過時間)から次の状態と出来事を導く純粋計算(M遷移関数の型シグネチャを満たす)。
    /// 受け取った状態か命令が規則の地図に無い経路を指していれば、受け取った状態をそのまま遷移失敗結果にして返す。
    pub fn 開閉を遷移する(
        self,
        命令: &経路の開閉の命令,
        規則: &経路の開閉の規則,
        パラメータ: 遷移パラメータ,
    ) -> Result<遷移成功結果<経路の開閉の状態, 経路の開閉の出来事>, 遷移失敗結果<経路の開閉の状態, 経路の指定の失敗>> {
        if let Err(失敗の理由) = 規則.状態と命令が指す経路を確かめる(&self, 命令) {
            return Err(遷移失敗結果 { 元の状態: self, 失敗の理由 });
        }
        let 命令が指す経路 = 命令.指す経路();
        let mut 変化一覧 = 規則.この刻みに時刻が起こす変化一覧(パラメータ);
        変化一覧.retain(|変化| !self.出来事が触れた経路.contains(&変化.経路) && 命令が指す経路 != Some(&変化.経路));
        変化一覧.extend(命令.開閉の変化());
        let mut 触れた経路の前の開閉 = BTreeMap::new();
        for 変化 in &変化一覧 {
            触れた経路の前の開閉.entry(変化.経路.clone()).or_insert_with(|| self.経路の開閉(&変化.経路));
        }
        let mut 閉じている経路 = self.閉じている経路;
        for 変化 in 変化一覧 {
            match 変化.変わる先 {
                経路の開閉::閉じている => 閉じている経路.insert(変化.経路),
                経路の開閉::開いている => 閉じている経路.remove(&変化.経路),
            };
        }
        let mut 出来事が触れた経路 = self.出来事が触れた経路;
        出来事が触れた経路.extend(命令が指す経路.cloned());
        let 次の状態 = Self {
            閉じている経路, 出来事が触れた経路
        };
        let 出来事一覧 = 触れた経路の前の開閉.into_iter().filter_map(|(経路, 前)| {
            let 後 = 次の状態.経路の開閉(&経路);
            経路の開閉の出来事::前後の開閉の差から組む(経路, 前, 後)
        });
        let 出来事一覧 = 出来事一覧.collect();
        Ok(遷移成功結果 { 次の状態, 出来事一覧 })
    }
}

