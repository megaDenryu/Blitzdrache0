use super::通り口::通り口の開閉の対象;
use super::通れる通り口::通れる通り口の集合;
use super::開閉の予定::経路の開閉;
use super::開閉の出来事::経路の開閉の出来事;
use super::開閉の命令::経路の開閉の命令;
use super::開閉の状態の指定::経路の開閉の状態の指定;
