//! 旅の1刻みの組み立て。経路の開閉の遷移と旅行者の歩行の遷移を、1刻みの中で決まった順に進める工程である(Issue #187 の作業G2)。
//!
//! 順序は「開閉を遷移する → 通れる通り口を導く → 歩行を遷移する」である。この順序は、門が閉じる刻みに旅行者が門を通ろうとした場合の結果を決める。
//! 閉じる刻みの歩行は、閉じた後の通り口で判断され、門で遮られる。
//! 通れる通り口を導き直すのは、開閉の遷移が出来事(経路が閉じた・開いた)を生んだ刻みだけである。出来事は前後の開閉の差からだけ生じるため、
//! 出来事が無い刻みは通れる通り口も変わらず、毎刻み全部を作り直さずに済む。
//! 2つの遷移の失敗は互いに独立に扱う。開閉の遷移が命令を拒んでも(命令が地図に無い経路を指したとき)、開閉の状態はそのまま歩行を進め、
//! 歩行の遷移が失敗しても、開閉の遷移の結果は残す。門は旅行者の失敗に関わらず予定どおりに閉じるためである。
//! この型はドメインの遷移ではなく、2つの遷移を組み立てる工程(`M工程`)であり、ドメインの遷移のモジュールと分けて置く。

use blitz_design::M工程;

use crate::transition_parameter::遷移パラメータ;
use crate::traveler::{旅行者の出来事, 旅行者の意図, 歩行の規則};
use crate::traveler_error::歩行の失敗;
use crate::traveler_movement::歩行遷移の規則;
use crate::地点と経路::指定の失敗::経路の指定の失敗;
use crate::地点と経路::空間制約::区域の空間制約;
use crate::地点と経路::開閉の出来事::経路の開閉の出来事;
use crate::地点と経路::開閉の命令::経路の開閉の命令;
use crate::地点と経路::開閉の状態::経路の開閉の状態;
use crate::地点と経路::開閉の規則::経路の開閉の規則;
use crate::居場所::旅行者の居場所;

/// 経路の開閉の状態と旅行者の居場所と、開閉の状態から導いた歩行の規則を持ち、1刻みずつ進める工程。
#[derive(Clone)]
pub struct 旅の進行 {
    開閉の規則: 経路の開閉の規則,
    開閉の状態: 経路の開閉の状態,
    居場所: 旅行者の居場所,
    歩行遷移の規則: 歩行遷移の規則,
}

impl M工程 for 旅の進行 {}

/// 旅の進行を始めるための指定。開閉の状態は、その規則から作ったものを渡す。
pub struct 旅の進行の指定 {
    pub 開閉の規則: 経路の開閉の規則,
    pub 開閉の状態: 経路の開閉の状態,
    pub 居場所: 旅行者の居場所,
    pub 身体: 歩行の規則,
}

/// 1刻みに与える入力。開閉の命令(出来事から作られる)と、旅行者の意図である。
pub struct 旅の一刻みの入力 {
    pub 開閉の命令: 経路の開閉の命令,
    pub 旅行者の意図: 旅行者の意図,
}

/// 1刻みで2つの遷移のどちらかが失敗した理由。
#[derive(Debug, Clone, PartialEq)]
pub enum 旅の一刻みの失敗 {
    開閉を遷移できなかった(経路の指定の失敗),
    歩行を遷移できなかった(歩行の失敗),
}

/// 1刻み進めた結果。次の進行と、その刻みで生じた出来事と、失敗した遷移の理由を持つ。
pub struct 旅の一刻みの結果 {
    pub 次の進行: 旅の進行,
    pub 開閉の出来事一覧: Vec<経路の開閉の出来事>,
    pub 旅行者の出来事一覧: Vec<旅行者の出来事>,
    pub 失敗一覧: Vec<旅の一刻みの失敗>,
}

impl 旅の進行 {
    /// 指定の開閉の状態から、いま通れる通り口を導いて歩行の規則を組み、進行を始める。
    pub fn 始める(指定: 旅の進行の指定) -> Self {
        let 空間制約 = 区域の空間制約::開閉の状態から導く(指定.開閉の規則.地図().clone(), &指定.開閉の状態);
        Self {
            開閉の規則: 指定.開閉の規則,
            開閉の状態: 指定.開閉の状態,
            居場所: 指定.居場所,
            歩行遷移の規則: 歩行遷移の規則::生成する(指定.身体, 空間制約),
        }
    }

    pub fn 開閉の状態(&self) -> &経路の開閉の状態 {
        &self.開閉の状態
    }

    pub fn 居場所(&self) -> &旅行者の居場所 {
        &self.居場所
    }

    pub fn 歩行遷移の規則(&self) -> &歩行遷移の規則 {
        &self.歩行遷移の規則
    }

    /// 開閉を遷移し、開閉が変わったなら通れる通り口を導き直し、歩行を遷移する。
    pub fn 一刻み進める(self, 入力: &旅の一刻みの入力, パラメータ: 遷移パラメータ) -> 旅の一刻みの結果 {
        let mut 失敗一覧 = Vec::new();
        let (開閉の状態, 開閉の出来事一覧) = match self.開閉の状態.開閉を遷移する(&入力.開閉の命令, &self.開閉の規則, パラメータ) {
            Ok(成功) => (成功.次の状態, 成功.出来事一覧),
            Err(失敗) => {
                失敗一覧.push(旅の一刻みの失敗::開閉を遷移できなかった(失敗.失敗の理由));
                (失敗.元の状態, Vec::new())
            }
        };
        let 歩行遷移の規則 = if 開閉の出来事一覧.is_empty() {
            self.歩行遷移の規則
        } else {
            self.歩行遷移の規則.通れる通り口を導き直す(&開閉の状態)
        };
        let (居場所, 旅行者の出来事一覧) = match self.居場所.歩行を遷移する(&入力.旅行者の意図, &歩行遷移の規則, パラメータ) {
            Ok(成功) => (成功.次の状態, 成功.出来事一覧),
            Err(失敗) => {
                失敗一覧.push(旅の一刻みの失敗::歩行を遷移できなかった(失敗.失敗の理由));
                (失敗.元の状態, Vec::new())
            }
        };
        旅の一刻みの結果 {
            次の進行: Self {
                開閉の規則: self.開閉の規則,
                開閉の状態,
                居場所,
                歩行遷移の規則,
            },
            開閉の出来事一覧,
            旅行者の出来事一覧,
            失敗一覧,
        }
    }
}
