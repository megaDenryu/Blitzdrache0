//! 地面を上から見た平面の幾何。点・線分・単純多角形と、点の位置・線分の区切り・多角形の重なり・境界に沿わせる動きの計算を持つ。
//!
//! このモジュールは区域と歩行を支える仕組みの層であり、Escaの語彙(地点・経路・旅行者)を1つも知らない(設計正本 4.3 の抽象度レイヤーの純化)。
//! 区域(`地点と経路::区域`)が単純多角形を包み、区域の中の移動がここの計算を呼ぶ。
//! ここの型に設計解釈マーカーを付けないのは、どれもドメインの概念ではなく計算の道具だからである。
//! 境界の上かどうかの判断は、どこも同じ境界の許容幅(`点と線分.rs` の `境界の許容幅`)で行う。判断が場所ごとに違うと、ある計算が境界の上と見た点を別の計算が外側と見る食い違いが起きるためである。
//! 例外は移動の終点が閉包に着いたかの判断だけであり、境界の許容幅の半分(`着く点の許容幅`)で行う。着いた点が単精度へ戻って動いても、次の移動の始点として境界の許容幅の中に残るようにするためである。

