//! ゲーム『Esca』が `blitz_design` の共通の設計語彙へ足す、遷移関数の役割 (Issue #137)。
//!
//! 共通の設計解釈マーカー(`M不変データ`・`M状態`・`Mコマンド`・`Mイベント`・`M規則`・`M入力`)と射影・解釈の役割の newtype は
//! `blitz_design` に在る。遷移関数だけをここに残すのは、この型が「状態とコマンドと規則と遷移パラメータから
//! 次の状態と出来事を導く」という計算モデルまで固定しており、まず Esca で形を確かめてから昇格を判断する
//! というオーナーの裁定による。遷移パラメータの一般形(どの入力を含めるか)が未確定であることも、昇格を待つ理由である。
//! 遷移は数値の表現範囲を超えるなどで失敗しうるため、戻り値は `Result<遷移成功結果, 失敗>` であり、失敗側の型を遷移失敗結果と呼ぶ。
//! 参照: `_doc/設計/設計オントロジー.md` 3.5.1・3.5.9。
//!
//! # 法則の検査主体
//! コンパイラが強制する法則:
//! 1. `M不変データ` は `Clone` を持つ(上位トレイト)。
//! 2. `M状態`・`Mコマンド`・`Mイベント`・`M規則`・`M入力`・`M設定` は `M不変データ` を実装する(上位トレイト)。
//! 3. 関数の役割(`M遷移関数` 等)は境界付きの newtype であり、型を使った時点で型引数が役割を満たす。迂回できる書き方は無い。
//! 4. `遷移成功結果` の型引数は `M状態`・`Mイベント` を満たす(構造体の境界)。
//!
//! `cargo xtask conform` の設計オントロジーの検査が見る法則:
//! 5. `M不変データ` またはデータの役割を実装する型の定義は参照・生ポインタ・内部可変性を持たない(検査器は役割の実装から型の定義をたどって当てる)。
//! 6. `Mコマンド` は `enum`、`M規則` は `struct` である。
//! 7. `M不変データ` を実装する型(データの役割を実装する型をすべて含む)の固有の `impl` とトレイトの実装は `&mut self` を持たない。

use crate::transition_parameter::遷移パラメータ;
use blitz_design::{Mイベント, Mコマンド, M状態, M規則};

/// 遷移関数が返す、次の状態と、その遷移で生じた出来事の一覧の組。生のタプルで返さないための名前付きの結果であり、
/// 型引数に `M状態`・`Mイベント` の境界を持つ意味型である。境界は構造体の利用箇所でコンパイラが強制する。
#[derive(Debug, Clone, PartialEq)]
pub struct 遷移成功結果<状態: M状態, イベント: Mイベント> {
    pub 次の状態: 状態,
    pub 出来事一覧: Vec<イベント>,
}

/// (状態, コマンド, 規則, 遷移パラメータ) から次の状態と出来事を導く純粋計算。遷移パラメータは必須入力の束(`MParameter`)であり、Esca第1段階では有限かつ0以上を型で保証した `経過時間` を持つ。
/// 遷移は数値の表現範囲を超えたときなどに失敗しうるため、失敗を `std::error::Error` の型引数で返す。型引数の境界は利用箇所でコンパイラが強制する。
#[derive(Clone, Copy)]
pub struct M遷移関数<状態: M状態, コマンド: Mコマンド, 規則: M規則, イベント: Mイベント, 失敗: std::error::Error>(遷移の関数ポインタ<状態, コマンド, 規則, イベント, 失敗>);

/// `M遷移関数` が包む関数ポインタの型。境界は `M遷移関数` の宣言が持ち、この別名は型の書き方を1箇所にまとめるだけである。
pub type 遷移の関数ポインタ<状態, コマンド, 規則, イベント, 失敗> = fn(&状態, &コマンド, &規則, 遷移パラメータ) -> Result<遷移成功結果<状態, イベント>, 失敗>;

impl<状態: M状態, コマンド: Mコマンド, 規則: M規則, イベント: Mイベント, 失敗: std::error::Error> M遷移関数<状態, コマンド, 規則, イベント, 失敗> {
    /// 関数を遷移の役割で包む。
    pub const fn 生成する(関数: 遷移の関数ポインタ<状態, コマンド, 規則, イベント, 失敗>) -> Self {
        Self(関数)
    }

    /// 包んだ関数を状態・コマンド・規則・遷移パラメータへ適用し、遷移成功結果か遷移失敗結果を得る。
    pub fn 呼び出す(&self, 状態: &状態, コマンド: &コマンド, 規則: &規則, パラメータ: 遷移パラメータ) -> Result<遷移成功結果<状態, イベント>, 失敗> {
        (self.0)(状態, コマンド, 規則, パラメータ)
    }
}
