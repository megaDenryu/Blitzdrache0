//! ゲーム『Esca』が `blitz_design` の共通の設計語彙へ足す、遷移関数の役割 (Issue #137)。
//!
//! 共通の設計マーカー(`MDTO`・`M状態`・`Mコマンド`・`Mイベント`・`M規則`・`M入力`)と射影・解釈の関数型は
//! `blitz_design` に在る。遷移関数だけをここに残すのは、この関数型が「状態とコマンドと規則と経過時間から
//! 次の状態と出来事を導く」という計算モデルまで固定しており、まず Esca で形を確かめてから昇格を判断する
//! というオーナーの裁定による。
//!
//! # 法則の検査主体
//! コンパイラが強制する法則:
//! 1. `MDTO` と `Mイベント` は `Clone` を持つ(上位トレイト)。
//! 2. `M状態` と `M入力` は `MDTO` を実装する(上位トレイト)。
//! 3. 関数型の型引数は役割を満たす(`遷移関数として確認する` 等の恒等の関数の境界)。
//!
//! `cargo xtask conform` の設計オントロジーの検査が見る法則:
//! 4. `MDTO` と `Mイベント` の定義は参照・生ポインタ・内部可変性を持たない。
//! 5. `Mコマンド` は `enum`、`M規則` は `struct` である。
//! 6. マーカーを実装する型の固有の `impl` は `&mut self` を持たない。

use blitz_design::{Mイベント, Mコマンド, M状態, M規則};
use blitz_math::秒;

/// 遷移関数が返す、次の状態と、その遷移で生じた出来事の一覧の組。生のタプルで返さないための名前付きの結果である。
#[derive(Debug, Clone, PartialEq)]
pub struct 遷移結果<状態, イベント> {
    pub 次の状態: 状態,
    pub 出来事一覧: Vec<イベント>,
}

/// (状態, コマンド, 規則, 経過時間) から次の状態と出来事を導く純粋計算の関数型。
pub type M遷移関数<状態, コマンド, 規則, イベント> = fn(&状態, &コマンド, &規則, 秒) -> 遷移結果<状態, イベント>;

/// 遷移関数の型引数が `M状態`・`Mコマンド`・`M規則`・`Mイベント` を満たすことをコンパイラに確かめさせる恒等の関数。
pub const fn 遷移関数として確認する<状態: M状態, コマンド: Mコマンド, 規則: M規則, イベント: Mイベント>(
    関数: M遷移関数<状態, コマンド, 規則, イベント>
) -> M遷移関数<状態, コマンド, 規則, イベント> {
    関数
}
