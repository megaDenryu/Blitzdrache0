//! ゲーム『Esca』が `blitz_design` の共通の設計語彙へ足す、遷移関数の役割 (Issue #137)。
//!
//! 共通の設計マーカー(`MDTO`・`M状態`・`Mコマンド`・`Mイベント`・`M規則`・`M入力`)と射影・解釈の役割の newtype は
//! `blitz_design` に在る。遷移関数だけをここに残すのは、この型が「状態とコマンドと規則と経過時間から
//! 次の状態と出来事を導く」という計算モデルまで固定しており、まず Esca で形を確かめてから昇格を判断する
//! というオーナーの裁定による。遷移文脈(経過時間の一般形)が未確定であることも、昇格を待つ理由である。
//!
//! # 法則の検査主体
//! コンパイラが強制する法則:
//! 1. `MDTO` は `Clone` を持つ(上位トレイト)。
//! 2. `M状態`・`Mコマンド`・`Mイベント`・`M規則`・`M入力`・`M設定` は `MDTO` を実装する(上位トレイト)。
//! 3. 関数の役割(`M遷移関数` 等)は境界付きの newtype であり、型を使った時点で型引数が役割を満たす。迂回できる綴りは無い。
//! 4. `遷移結果` の型引数は `M状態`・`Mイベント` を満たす(構造体の境界)。
//!
//! `cargo xtask conform` の設計オントロジーの検査が見る法則:
//! 5. `MDTO` の定義は参照・生ポインタ・内部可変性を持たない(上位トレイトにより各役割の型を含む)。
//! 6. `Mコマンド` は `enum`、`M規則` は `struct` である。
//! 7. `Mコマンド`・`Mイベント`・`M規則`・`M設定` を実装する型の固有の `impl` は `&mut self` を持たない。
//! 8. 役割のマーカーを実装する型は `impl MDTO for` も書いている(検査器が `MDTO` の一覧から見落とさないため)。

use crate::elapsed_time::経過時間;
use blitz_design::{Mイベント, Mコマンド, M状態, M規則};

/// 遷移関数が返す、次の状態と、その遷移で生じた出来事の一覧の組。生のタプルで返さないための名前付きの結果であり、
/// 型引数に `M状態`・`Mイベント` の境界を持つ意味型である。境界は構造体の利用箇所でコンパイラが強制する。
#[derive(Debug, Clone, PartialEq)]
pub struct 遷移結果<状態: M状態, イベント: Mイベント> {
    pub 次の状態: 状態,
    pub 出来事一覧: Vec<イベント>,
}

/// (状態, コマンド, 規則, 経過時間) から次の状態と出来事を導く純粋計算。経過時間は有限かつ0以上を型で保証した `経過時間` で受ける。
/// 型引数の境界は利用箇所でコンパイラが強制する。
#[derive(Clone, Copy)]
pub struct M遷移関数<状態: M状態, コマンド: Mコマンド, 規則: M規則, イベント: Mイベント>(fn(&状態, &コマンド, &規則, 経過時間) -> 遷移結果<状態, イベント>);

impl<状態: M状態, コマンド: Mコマンド, 規則: M規則, イベント: Mイベント> M遷移関数<状態, コマンド, 規則, イベント> {
    /// 関数を遷移の役割で包む。
    pub const fn 生成する(関数: fn(&状態, &コマンド, &規則, 経過時間) -> 遷移結果<状態, イベント>) -> Self {
        Self(関数)
    }

    /// 包んだ関数を状態・コマンド・規則・経過時間へ適用し、遷移結果を得る。
    pub fn 呼び出す(&self, 状態: &状態, コマンド: &コマンド, 規則: &規則, 経過時間: 経過時間) -> 遷移結果<状態, イベント> {
        (self.0)(状態, コマンド, 規則, 経過時間)
    }
}
