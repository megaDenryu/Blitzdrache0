//! ゲーム『Esca』のプログラミング設計オントロジー (Issue #137)。
//!
//! 構文解析器で機械的に抽出可能な、プログラム構造上の役割マーカー群。
//! 無理な継承関係を持たせず、直交する設計概念として定義する。
//!
//! # 構文法則(Law)
//! 1. `MDTO`: 参照(&)・ポインタ(*)・内部可変性を持たず、Cloneを導出すること。
//! 2. `M状態`: 必ず境界を越えるデータとして `MDTO` も実装すること。
//! 3. `Mコマンド`: 必ず選択肢を表す `enum` であり、`&mut self` を持たないこと。
//! 4. `Mイベント`: 過去の事実を表すため、`&mut self` を持たず Clone を導出すること。
//! 5. `M規則`: 不変法則であるため、必ず `struct` であり、`&mut self` を持たないこと。
//! 6. `M入力`: デバイス境界の生シグナルであり、必ず `MDTO` を実装すること。
//! 7. `M遷移関数`: `(M状態, Mコマンド, M規則, 秒数) -> (M状態, Vec<Mイベント>)` の純粋計算関数。
//! 8. `M射影関数`: `&M状態 -> MDTO` の一方向変換関数。
//! 9. `M解釈関数`: `&M入力 -> Mコマンド` の一方向解釈関数。

/// プログラミング設計上の役割: 境界を越えて運ばれる純粋なデータ構造体。
pub trait MDTO {}

/// プログラミング設計上の役割: ゲーム世界に実在し、保持・遷移される状態 (状態 is a DTO)。
pub trait M状態: MDTO {}

/// プログラミング設計上の役割: 主体が選択・発行する命令、意図、アクション。
pub trait Mコマンド {}

/// プログラミング設計上の役割: ある瞬間のみ発生し、消費される一過性の刺激、事実。
pub trait Mイベント {}

/// プログラミング設計上の役割: 計算や状態遷移を律する不変のルール、法則、ポリシー。
pub trait M規則 {}

/// プログラミング設計上の役割: 外界(入力デバイス等)から届くゲーム意味論を持たない生シグナル。
pub trait M入力: MDTO {}

/// プログラミング設計上の役割: (状態, コマンド, 規則, 時間)から次状態と出来事を導出する純粋計算の関数型。
///
/// 【型引数にトレイト境界(状態: M状態 等)を付けない理由】
/// Rustの言語仕様上、型エイリアス(`type`)のトレイト境界はコンパイラにより無視され強制されません
/// (Rust Issue #112792: type alias bounds are not enforced)。
/// そのため、型エイリアス定義自体は境界なしの型引数とし、構文解析器(syntax_checker / Law 7)が
/// 静的型宣言(`const _: M遷移関数<...>`)を走査して各型引数がオントロジーを満たすことを機械検証します。
pub type M遷移関数<状態, コマンド, 規則, イベント> =
    fn(&状態, &コマンド, &規則, f32) -> (状態, Vec<イベント>);

/// プログラミング設計上の役割: 内部状態から外部(描画・UI)向け表示DTOを取り出す一方向射影の関数型。
///
/// 【型引数にトレイト境界を付けない理由】
/// 上記の `M遷移関数` と同様、Rustコンパイラが型エイリアスの境界検査を強制しないため、
/// 構文解析器(Law 8)により `状態: M状態`, `射影DTO: MDTO` であることを機械検証します。
pub type M射影関数<状態, 射影DTO> = fn(&状態) -> 射影DTO;

/// プログラミング設計上の役割: 外界の生入力からゲームのコマンド(意志)を導出する純粋計算の関数型。
///
/// 【型引数にトレイト境界を付けない理由】
/// 上記と同様、構文解析器(Law 9)により `入力: M入力`, `コマンド: Mコマンド` であることを機械検証します。
pub type M解釈関数<入力, コマンド> = fn(&入力) -> コマンド;

/// 構文解析器で機械検証の対象となるオントロジーのマーカートレイト一覧。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum オントロジートレイト {
    MDTO,
    M状態,
    Mコマンド,
    Mイベント,
    M規則,
    M入力,
}

impl オントロジートレイト {
    /// ソースコード構文解析で照合するためのトレイト識別子文字列を返す。
    pub const fn 名前(self) -> &'static str {
        match self {
            Self::MDTO => "MDTO",
            Self::M状態 => "M状態",
            Self::Mコマンド => "Mコマンド",
            Self::Mイベント => "Mイベント",
            Self::M規則 => "M規則",
            Self::M入力 => "M入力",
        }
    }
}

