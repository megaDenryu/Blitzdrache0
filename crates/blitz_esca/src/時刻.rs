//! 世界の時刻。世界が始まってから経った時間であり、有限かつ0以上を不変条件に持つ値オブジェクトである。
//! 経過時間(1回の遷移が進める時間の長さ)と別の型にするのは、時刻どうしの前後の比較と、時刻に長さを足して次の時刻を得る演算は意味を持つが、
//! 時刻どうしを足す演算は意味を持たないためである。経路の閉じている時間帯の端と、遷移パラメータが持つ刻みの始まりの時刻がこの型で表される。
//!
//! 中身を倍精度の `大域秒`(永続世界の絶対時刻の単位型)で持つ。単精度の秒では、約2^19秒(約6日)から先で表現の刻みが1/32秒を超え、
//! 始まりの時刻に1/60秒を足しても始まりの時刻のままになる。すると刻みの区間が空になり、その刻みに来るはずの時刻の予定が来なくなるためである。

use blitz_design::{M不変データ, M値オブジェクト};
use blitz_math::大域秒;

use crate::elapsed_time::経過時間;

/// 世界が始まってから経った、有限かつ0以上の時間。`生成する` を通らずには作れない。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 世界の時刻(大域秒);

impl M不変データ for 世界の時刻 {}
impl M値オブジェクト for 世界の時刻 {}

impl 世界の時刻 {
    /// 値が有限かつ0以上であることを確かめて時刻を作る。
    pub fn 生成する(値: 大域秒) -> Result<Self, 世界の時刻の生成の失敗> {
        let 生値 = 値.値();
        if !生値.is_finite() || 生値 < 0.0 {
            return Err(世界の時刻の生成の失敗::有限な0以上の数値でない { 値 });
        }
        Ok(Self(値))
    }

    /// 世界が始まった時刻(0秒)。
    pub fn 世界の始まり() -> Self {
        Self(大域秒::生成する(0.0))
    }

    /// この時刻から経過時間だけ進んだ時点の大域秒。呼ぶのは遷移パラメータの刻みの終わりを求める口だけであり、
    /// 刻みの終わりと次の刻みの始まりを同じ1つの足し算から作る(別の数え方で次の始まりを作ると、隣り合う刻みの区間に隙間か重なりができる)。
    /// 和は倍精度の表現範囲を超えて無限大になりうるため、時刻の型でなく大域秒で返す。
    pub(crate) fn 経過時間だけ進んだ大域秒(&self, 経過: 経過時間) -> 大域秒 {
        self.0 + 大域秒::生成する(f64::from(経過.秒().値()))
    }

    pub fn 大域秒(&self) -> 大域秒 {
        self.0
    }
}

/// 世界の時刻の値が不変条件を満たさなかった理由。
#[derive(Debug, Clone, Copy, PartialEq, thiserror::Error)]
pub enum 世界の時刻の生成の失敗 {
    #[error("世界の時刻{値:?}が有限な0以上の数値でない(世界の時刻は有限かつ0以上でなければならない)")]
    有限な0以上の数値でない { 値: 大域秒 },
}
