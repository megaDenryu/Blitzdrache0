//! 主人公(旅行者)の移動意図・現在地・歩行規則(判断: Esca設計正本)。
//!
//! プログラミング設計上の役割(コマンド、状態+DTO、規則、イベント)に従って定義する。

use blitz_design::{Mイベント, Mコマンド, M不変データ, M値オブジェクト, M規則};
use blitz_math::{メートル, メートル毎秒, 大域メートル};

use crate::traveler_error::{旅行者の現在地の生成の失敗, 歩行の規則の生成の失敗};
use crate::walking_direction::歩行方向;
use crate::平面の幾何::点と線分::平面の点;

/// 旅行者が行おうとするアクション(命令・意図)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 旅行者の意図 {
    静止,
    歩く { 方向: 歩行方向 },
    見回す,
}

impl M不変データ for 旅行者の意図 {}
impl Mコマンド for 旅行者の意図 {}

/// 旅行者のワールド内の現在地。東と北が有限な数値であることを不変条件に持つ値オブジェクトであり、歩行の遷移の状態(`旅行者の居場所`)がいる地点と組にして持つ。
/// フィールドは私有であり、`生成する` と `平行移動する` の検証を通らずには作れない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 旅行者の現在地 {
    東: メートル,
    北: メートル,
}

/// 現在地を平行移動する変位。東と北の2成分を1つの概念として束ね、同型の2引数の取り違えを防ぐ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 移動の変位 {
    pub 東: メートル,
    pub 北: メートル,
}

impl M不変データ for 移動の変位 {}

impl M不変データ for 旅行者の現在地 {}
impl M値オブジェクト for 旅行者の現在地 {}

impl 旅行者の現在地 {
    /// 東と北が有限な数値であることを確かめて現在地を作る。NaN は比較がすべて偽になり区域の閉包の判定が正しく働かないため、生成の口で閉じる。
    pub fn 生成する(東: メートル, 北: メートル) -> Result<Self, 旅行者の現在地の生成の失敗> {
        if !東.値().is_finite() || !北.値().is_finite() {
            return Err(旅行者の現在地の生成の失敗::座標が有限な数値でない { 東, 北 });
        }
        Ok(Self { 東, 北 })
    }

    /// 変位を足した現在地を作る。有限な入力の和でも `f32` は無限大になりうるため、`生成する` と同じ検証を通す。
    pub fn 平行移動する(&self, 変位: 移動の変位) -> Result<Self, 旅行者の現在地の生成の失敗> {
        Self::生成する(self.東 + 変位.東, self.北 + 変位.北)
    }

    pub fn 東(&self) -> メートル {
        self.東
    }

    pub fn 北(&self) -> メートル {
        self.北
    }

    /// 区域の計算に渡すため、東と北を倍精度の平面の点へ広げる。広げる変換は値を変えない。
    pub fn 平面の点へ広げる(&self) -> 平面の点 {
        平面の点 {
            東: 大域メートル::メートルから広げる(self.東),
            北: 大域メートル::メートルから広げる(self.北),
        }
    }

    /// 区域の計算が返した平面の点を、最も近い単精度の現在地へ狭める。単精度の表現範囲を超える点は現在地にならず失敗する。
    pub fn 平面の点から狭める(点: &平面の点) -> Result<Self, 旅行者の現在地の生成の失敗> {
        match (点.東.メートルへ狭める(), 点.北.メートルへ狭める()) {
            (Ok(東), Ok(北)) => Self::生成する(東, 北),
            _ => Err(旅行者の現在地の生成の失敗::座標が単精度で表せない { 東: 点.東, 北: 点.北 }),
        }
    }
}

/// 旅行者が歩く際の規則(身体の運動法則)。遷移からは読み取り専用で与えられる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 歩行の規則 {
    一秒あたりの速さ: メートル毎秒,
}

impl M不変データ for 歩行の規則 {}
impl M規則 for 歩行の規則 {}

impl 歩行の規則 {
    pub fn 標準() -> Self {
        Self {
            一秒あたりの速さ: メートル毎秒::生成する(3.0)
        }
    }

    /// 速さが有限かつ0以上であることを確かめて規則を作る。0を許すのは、静止は `旅行者の意図::静止` で表すため速さ0の規則が矛盾を生まないことによる。
    pub fn 生成する(一秒あたりの速さ: メートル毎秒) -> Result<Self, 歩行の規則の生成の失敗> {
        let 値 = 一秒あたりの速さ.値();
        if !値.is_finite() || 値 < 0.0 {
            return Err(歩行の規則の生成の失敗::速さが有限な0以上の数値でない { 速さ: 一秒あたりの速さ });
        }
        Ok(Self { 一秒あたりの速さ })
    }

    pub fn 速さ(&self) -> メートル毎秒 {
        self.一秒あたりの速さ
    }
}

/// 旅行者の行動によって世界に発生した出来事(過去の事実)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 旅行者の出来事 {
    /// 見回す意図の遷移で、旅行者が周囲を観察した事実。
    周囲を観察した,
    /// 移動先へ向かう動きが区域の越えられない境目に当たり、実際の移動位置が境目で止められた事実。
    障害物に遮られた,
}

impl M不変データ for 旅行者の出来事 {}
impl Mイベント for 旅行者の出来事 {}
