//! スモーク用四角形(1辺1m・原点中心・法線+Z)の頂点データをglTFの
//! バッファバイト列へ直列化する。区間の並び順(位置→法線→接線→UV→インデックス)と
//! 各区間のバイト長はgltf_jsonのbufferViewsへ手動で一致させている。

/// 位置・法線・接線・UV・インデックスを連結した.binの中身を作る。
pub(super) fn バッファバイト列を作る() -> Vec<u8> {
    let 位置一覧: [[f32; 3]; 4] = [
        [-0.5, -0.5, 0.0],
        [0.5, -0.5, 0.0],
        [0.5, 0.5, 0.0],
        [-0.5, 0.5, 0.0],
    ];
    let 法線一覧: [[f32; 3]; 4] = [[0.0, 0.0, 1.0]; 4];
    // UのプラスがワールドX、VのプラスがワールドYに一致する構図のため、
    // 接線(dPos/dU)=(1,0,0)・w=+1(cross(法線,接線)がdPos/dVの(0,1,0)と一致)が
    // 幾何学的に正しい値になる(判断25)。
    let 接線一覧: [[f32; 4]; 4] = [[1.0, 0.0, 0.0, 1.0]; 4];
    let テクスチャ座標一覧: [[f32; 2]; 4] = [[0.0, 0.0], [1.0, 0.0], [1.0, 1.0], [0.0, 1.0]];
    let インデックス一覧: [u16; 6] = [0, 1, 2, 0, 2, 3];

    let mut バイト列 = Vec::with_capacity(204);
    for 位置 in 位置一覧 {
        for 成分 in 位置 {
            バイト列.extend_from_slice(&成分.to_le_bytes());
        }
    }
    for 法線 in 法線一覧 {
        for 成分 in 法線 {
            バイト列.extend_from_slice(&成分.to_le_bytes());
        }
    }
    for 接線 in 接線一覧 {
        for 成分 in 接線 {
            バイト列.extend_from_slice(&成分.to_le_bytes());
        }
    }
    for 座標 in テクスチャ座標一覧 {
        for 成分 in 座標 {
            バイト列.extend_from_slice(&成分.to_le_bytes());
        }
    }
    for インデックス in インデックス一覧 {
        バイト列.extend_from_slice(&インデックス.to_le_bytes());
    }
    バイト列
}
