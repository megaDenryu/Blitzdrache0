//! シャドウ検証アセット(判断37)の2プリミティブ(床quad・遮蔽quad)を連結した
//! .binの中身を作る。区間の並び順(位置→法線→接線→UV→インデックス、床→遮蔽)と
//! 各区間のバイト長はshadow_scene_gltf_jsonのbufferViewsへ手動で一致させている。

/// 床quad(XZ平面4m四方・y=0)と遮蔽quad(1m四方・y=1・床中央上に水平配置)の
/// 頂点・インデックスを連結した.binの中身を作る(各プリミティブ204バイト、計408バイト)。
pub(super) fn バッファバイト列を作る() -> Vec<u8> {
    let mut バイト列 = Vec::with_capacity(408);
    バイト列.extend(プリミティブ1つぶんを作る(
        [[-2.0, 0.0, 2.0], [2.0, 0.0, 2.0], [2.0, 0.0, -2.0], [-2.0, 0.0, -2.0]],
        [0.0, 1.0, 0.0],
    ));
    バイト列.extend(プリミティブ1つぶんを作る(
        [[-0.5, 1.0, 0.5], [0.5, 1.0, 0.5], [0.5, 1.0, -0.5], [-0.5, 1.0, -0.5]],
        [0.0, 1.0, 0.0],
    ));
    バイト列
}

/// 4頂点(位置→法線→接線→UV)とインデックス6個(204バイト)を直列化する。
/// 法線が+Yのため、UのプラスがワールドX・VのプラスがワールドZ逆向きに一致する
/// 構図で接線(1,0,0,1)が幾何学的に正しい値になる(既存quadと同じ考え方、判断25)。
fn プリミティブ1つぶんを作る(位置一覧: [[f32; 3]; 4], 法線: [f32; 3]) -> Vec<u8> {
    let 法線一覧 = [法線; 4];
    let 接線一覧: [[f32; 4]; 4] = [[1.0, 0.0, 0.0, 1.0]; 4];
    let テクスチャ座標一覧: [[f32; 2]; 4] = [[0.0, 0.0], [1.0, 0.0], [1.0, 1.0], [0.0, 1.0]];
    let インデックス一覧: [u16; 6] = [0, 1, 2, 0, 2, 3];

    let mut バイト列 = Vec::with_capacity(204);
    for 位置 in 位置一覧 {
        for 成分 in 位置 {
            バイト列.extend_from_slice(&成分.to_le_bytes());
        }
    }
    for 法線 in 法線一覧 {
        for 成分 in 法線 {
            バイト列.extend_from_slice(&成分.to_le_bytes());
        }
    }
    for 接線 in 接線一覧 {
        for 成分 in 接線 {
            バイト列.extend_from_slice(&成分.to_le_bytes());
        }
    }
    for 座標 in テクスチャ座標一覧 {
        for 成分 in 座標 {
            バイト列.extend_from_slice(&成分.to_le_bytes());
        }
    }
    for インデックス in インデックス一覧 {
        バイト列.extend_from_slice(&インデックス.to_le_bytes());
    }
    バイト列
}
