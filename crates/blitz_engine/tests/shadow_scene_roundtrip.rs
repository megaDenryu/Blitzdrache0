//! シャドウ検証アセット(judgment37)の往復テスト: 生成器→ローダで
//! 2プリミティブ(床・遮蔽)の頂点数・インデックスオフセットが正しく連結されることを確認する。
//!
//! 注意: `cargo test`のテストバイナリはパッケージディレクトリを作業ディレクトリとして
//! 実行される（リポジトリルートではない）ため、`CARGO_MANIFEST_DIR`からの相対パスで
//! リポジトリルート直下のassets/を参照する。

use std::path::PathBuf;

use blitz_engine::{アセットID, カタログ, シーンを読み込む, マテリアルデータ};

fn リポジトリルートからのパス(相対パス: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..").join(相対パス)
}

fn 試験用カタログ() -> (カタログ, アセットID) {
    let id = match アセットID::生成する("shadow_scene") {
        Ok(id) => id,
        Err(誤り) => panic!("試験用IDの生成に失敗した: {誤り}"),
    };
    let mut カタログ = カタログ::空を作る();
    カタログ.登録する(id.clone(), リポジトリルートからのパス("assets/smoke/shadow_scene.gltf"));
    (カタログ, id)
}

#[test]
fn 床と遮蔽の2プリミティブが頂点オフセット付きで連結される() {
    let (カタログ, id) = 試験用カタログ();

    let シーン = match シーンを読み込む(&カタログ, &id) {
        Ok(シーン) => シーン,
        Err(誤り) => panic!("assets/smoke/shadow_scene.gltfの読込に失敗した(cargo xtask gen-smoke-assetで生成済みか確認): {誤り}"),
    };

    // 床4頂点+遮蔽4頂点=8頂点、床6インデックス+遮蔽6インデックス=12インデックス。
    assert_eq!(シーン.メッシュ.頂点一覧.len(), 8);
    assert_eq!(シーン.メッシュ.インデックス一覧.len(), 12);

    // 前半6個(床)は0〜3の範囲、後半6個(遮蔽)は床の頂点数(4)ぶんオフセットされ4〜7の範囲。
    let (床側, 遮蔽側) = シーン.メッシュ.インデックス一覧.split_at(6);
    assert!(床側.iter().all(|&添字| 添字 < 4), "床側インデックスは0〜3のはず: {床側:?}");
    assert!(
        遮蔽側.iter().all(|&添字| (4..8).contains(&添字)),
        "遮蔽側インデックスは頂点オフセット4込みで4〜7のはず: {遮蔽側:?}"
    );

    // 床(先頭4頂点)はy=0、遮蔽(後続4頂点)はy=1に配置されている(判断37)。
    for 頂点 in &シーン.メッシュ.頂点一覧[..4] {
        assert_eq!(頂点.位置[1], 0.0, "床の頂点はy=0のはず");
    }
    for 頂点 in &シーン.メッシュ.頂点一覧[4..] {
        assert_eq!(頂点.位置[1], 1.0, "遮蔽の頂点はy=1のはず");
    }

    let マテリアルデータ::金属粗さPBR(マテリアル) = シーン.マテリアル;
    let ベースカラー = match マテリアル.ベースカラー {
        Some(テクスチャ) => テクスチャ,
        None => panic!("shadow_scene.gltfにはbaseColorテクスチャが設定されているはず"),
    };
    let 期待ピクセル = [255u8, 255, 255, 255];
    for ピクセル in ベースカラー.rgba8.chunks_exact(4) {
        assert_eq!(ピクセル, 期待ピクセル);
    }
}
