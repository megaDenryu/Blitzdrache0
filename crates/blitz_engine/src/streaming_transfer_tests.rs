use crate::streaming_chunk_world_fixture::{世界を作る, 後始末する};
use crate::streaming_coordinator_fixture::{準備完了を待つ, 起動する, 進める};
use crate::ストリーミングメモリ量;

#[test]
fn 読込とgpu転送と解除の累計を数える() {
    let (パス一覧, カタログ, 目録) = 世界を作る("transfer_total", &[(0, 0), (1, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(100_000, 100_000), 1);
    assert_eq!(調停.転送量(), Default::default());

    let 準備完了一覧 = 準備完了を待つ(&mut 調停, &カタログ, 50.0, 2);
    let 読込後 = 調停.転送量();
    assert_eq!(読込後.ディスク読込件数(), 2);
    // 読込バイト数は版付きファイル全体の長さの実測であり、見積とは一致しないため正であることだけを確かめる。
    assert!(読込後.ディスク読込バイト数() > 0);
    assert_eq!(読込後.gpu転送件数(), 0);

    for 座標 in 準備完了一覧 {
        let Ok(Some(_シーン)) = 調停.gpu転送のためにシーンデータを取り出す(座標) else {
            panic!("準備済みチャンクのシーンデータを取り出せなかった");
        };
        assert!(調停.gpu転送の完了を報告する(座標).is_ok());
    }
    let 転送後 = 調停.転送量();
    assert_eq!(転送後.gpu転送件数(), 2);
    assert!(転送後.gpu転送バイト数() > 0);
    assert_eq!(転送後.gpu解除件数(), 0);

    let 離脱 = 進める(&mut 調停, &カタログ, 100_050.0);
    for 座標 in 離脱.gpu資源解除待ち一覧() {
        assert!(調停.gpu資源の解除を報告する(*座標).is_ok());
    }
    assert_eq!(調停.転送量().gpu解除件数(), 2);
    // 累計は解除で減らない。過ぎ去った事象の合計であり、現在の保持量ではないためである。
    assert_eq!(調停.転送量().ディスク読込バイト数(), 読込後.ディスク読込バイト数());
    後始末する(&パス一覧);
}
