use super::チャンク座標;

#[test]
fn 番号への往復は負座標とi32両端で一致する() {
    for (x, z) in [
        (0, 0),
        (1, 2),
        (-1, -1),
        (i32::MIN, i32::MIN),
        (i32::MAX, i32::MAX),
        (i32::MIN, i32::MAX),
        (i32::MAX, i32::MIN),
        (-1, i32::MAX),
    ] {
        let 座標 = チャンク座標::生成する(x, z);
        let 復元 = チャンク座標::番号から復元する(座標.番号を返す());
        assert_eq!(復元, 座標);
        assert_eq!((復元.x(), 復元.z()), (x, z));
    }
}

#[test]
fn 四象限の異なる座標は互いに異なる番号になる() {
    let 座標一覧 = [(3, 5), (3, -5), (-3, 5), (-3, -5), (5, 3), (-5, -3), (0, 0)];
    let mut 番号一覧: Vec<u64> = 座標一覧.iter().map(|(x, z)| チャンク座標::生成する(*x, *z).番号を返す()).collect();
    番号一覧.sort_unstable();
    番号一覧.dedup();
    assert_eq!(番号一覧.len(), 座標一覧.len());
}

#[test]
fn 番号はxを上位32ビットzを下位32ビットへ置く() {
    assert_eq!(チャンク座標::生成する(0, 0).番号を返す(), 0);
    assert_eq!(チャンク座標::生成する(1, 2).番号を返す(), 0x0000_0001_0000_0002);
    assert_eq!(チャンク座標::生成する(-1, -1).番号を返す(), u64::MAX);
    assert_eq!(チャンク座標::生成する(-2, 3).番号を返す(), 0xFFFF_FFFE_0000_0003);
}
