//! リセット世代が古い読込完了を退けることを、アセットの内容が入れ替わる状況で確かめる。
//! 座標はリセットの前後で同じ値になるため、世代が無いと古い内容の完了が新しい読込の完了として受理される。

use crate::streaming_chunk_world_fixture::{
    世界を作る, 内容を変えたカタログを作る, 存在しない生成物のカタログを作る, 後始末する
};
use crate::streaming_coordinator_fixture::{準備完了を待つ, 起動する, 進める};
use crate::texture_storage::格納済みテクスチャ;
use crate::{シーンデータ, ストリーミングメモリ量, チャンク座標, マテリアルデータ};

/// 差し替え後のアセットが持つ画素。既定画素と異なる値であることが、どちらの完了を採用したかの判別根拠になる。
fn 差し替え後の画素() -> Vec<u8> {
    vec![200, 100, 50, 255]
}

fn ベースカラー画素(シーン: &シーンデータ) -> Vec<u8> {
    let Some(マテリアル) = シーン.先頭の描画対象().材質集合().唯一の材質() else {
        panic!("試験用チャンクシーンの材質集合が1件でなかった");
    };
    let マテリアルデータ::金属粗さPBR(材質) = マテリアル else {
        panic!("材質が金属粗さPBRの枝でない");
    };
    match 材質.ベースカラー.as_ref().and_then(格納済みテクスチャ::rgba8の原寸の画素列を返す) {
        Some(画素列) => 画素列.to_vec(),
        None => panic!("試験用チャンクシーンにRGBA8のベースカラーテクスチャが無かった"),
    }
}

#[test]
fn リセット前の読込失敗はエラーにならず新世代の完了を採用する() {
    let 座標 = チャンク座標::生成する(0, 0);
    let (パス一覧, 正カタログ, 目録) = 世界を作る("reset_gen_fail", &[(0, 0)]);
    let 壊れカタログ = 存在しない生成物のカタログを作る("reset_gen_fail", &[(0, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(100_000, 100_000), 1);
    // 存在しない生成物への読込を投入する。この完了は旧世代の失敗として届く。
    assert_eq!(進める(&mut 調停, &壊れカタログ, 50.0).読込開始一覧(), [座標]);
    調停.リセットする();

    // 旧世代の読込失敗が調停のエラーとして伝播すると、ここへ到達する前にフィクスチャが停止する。
    assert_eq!(準備完了を待つ(&mut 調停, &正カタログ, 50.0, 1), [座標]);
    let Ok(Some(_)) = 調停.gpu転送のためにシーンデータを取り出す(座標) else {
        panic!("新世代の完了が採用されなかった");
    };
    // 失敗した旧世代の読込はバイト数を持たないため、ディスク読込は新世代の1件だけを数える。
    assert_eq!(調停.転送量().ディスク読込件数(), 1);
    後始末する(&パス一覧);
}

#[test]
fn リセット後の読み直しは古い世代の完了を採用しない() {
    let 座標 = チャンク座標::生成する(0, 0);
    let (旧パス一覧, 旧カタログ, 目録) = 世界を作る("reset_generation", &[(0, 0)]);
    let (新パス一覧, 新カタログ) = 内容を変えたカタログを作る("reset_generation", &[(0, 0)], 差し替え後の画素());
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(100_000, 100_000), 1);
    assert_eq!(進める(&mut 調停, &旧カタログ, 50.0).読込開始一覧(), [座標]);
    // ここから先は差し替え後のアセットだけを読む。先に投入した読込は差し替え前の内容のまま完了する。
    調停.リセットする();

    assert_eq!(準備完了を待つ(&mut 調停, &新カタログ, 50.0, 1), [座標]);
    let Ok(Some(シーン)) = 調停.gpu転送のためにシーンデータを取り出す(座標) else {
        panic!("準備済みチャンクのシーンデータを取り出せなかった");
    };
    assert_eq!(ベースカラー画素(&シーン), 差し替え後の画素());
    // ワーカーは1本で要求順を保つため、差し替え前の完了は差し替え後の完了より先に届いて破棄されている。
    assert_eq!(調停.転送量().ディスク読込件数(), 2);
    後始末する(&旧パス一覧);
    後始末する(&新パス一覧);
}
