//! キャスター候補のカメラ距離分布を数える走査。受け取るのは可視個体の選別と同じ材料と積み先の分布であり、
//! 書き換えるのは分布だけである。1つの群につき1回呼ぶ。
//!
//! 本番の選択の走査へ条件を足さず別の走査として置くのは、選択の走査が個体1件あたり16ナノ秒台で回り、
//! 可視個体の選別2.0ミリ秒の予算の8割を占めているためである。距離分布は裁定の材料を一度採るためだけの計器であり、
//! 常時の費用を増やす理由が無い。判定そのものは選択と同じ`距離区分別の判定`を使うため、2つの走査が違う集合を数えることはない。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」

use super::band_pass_test::距離区分別の判定;
use super::camera_distance::{カメラからの距離, 基点にする};
use super::caster_distance::キャスター距離分布;
use super::combined_select::個体選択材料;
use super::pass_test::平行移動する;

pub fn キャスターのカメラ距離分布を数える(材料: &個体選択材料<'_>, 分布: &mut キャスター距離分布) {
    let 基点 = 基点にする(材料.カメラ相対の基準原点);
    let 距離区分別 = 距離区分別の判定::準備する(&材料.距離区分別の可視判定, 材料.材料.群の包囲領域(), 基点);
    for 球 in 材料.材料.個体境界球一覧() {
        let 中心 = 平行移動する(球.中心成分(), 基点);
        分布.個体を積む(カメラからの距離(中心), 距離区分別.個体のマスク(中心, 球.半径値()));
    }
}
