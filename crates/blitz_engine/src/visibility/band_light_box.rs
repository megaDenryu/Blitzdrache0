//! 4帯の正射影を、共有する光基底とその基底で見た帯ごとの区間で表した値。受け取るのは帯ごとのカメラ相対
//! ライトビュー射影4つ、返すのは個体の中心を1回写せば4帯すべてを区間比較だけで判定できる形である。
//!
//! 4帯の正射影は同じ方向光を見下ろすため、回転(光基底)を共有して平行移動と寸法だけが違う。この共有を使うと
//! 個体1件あたりの仕事が「行列の適用1回と区間比較4回」になる。帯ごとに視錐台の平面6枚を評価する形では
//! 個体1件あたりの平面評価が24枚になり、OW4で制定した群選択2.0ms予算を破る
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の帯別区間(4区分並べの後継)」)。
//!
//! 共有基底には帯0の軸を採る。帯1から帯3の直方体は、その基底で見た軸平行な区間へ写し直して保持する
//! (`rebase`)。写し直しは区間を外へ広げることしかしないため、判定は元の直方体に対して保守的である。

mod ortho_box;
mod rebase;

use blitz_math::{ワールド, 光源クリップ, 変換};
use blitz_render::cascade::{帯数, 帯番号};

use super::light_space_interval::光空間区間;

pub struct 帯別光空間直方体 {
    /// 4帯が共有する正規直交な光基底。1本の軸と点との内積が、光空間の座標のその成分になる。
    軸一覧: [[f32; 3]; 3],
    帯ごとの区間: [光空間区間; 帯数],
}

impl 帯別光空間直方体 {
    /// 帯ごとのライトビュー射影から作る。呼び出し元は、レンダラーがその帯のシャドウパスへ渡すのと同じ行列を
    /// 同じカメラ大域原点で組み立てて渡す責務を負う。判定に使う範囲と実際に描く範囲がずれると影が欠ける。
    /// 注意: カメラのビュー射影から導いてはならない。画面外の個体が画面内へ影を落とすためである。
    pub fn カメラ相対ライトビュー射影から生成する(帯ごと: [変換<ワールド, 光源クリップ>; 帯数]) -> Self {
        let 直方体一覧 = 帯ごと.map(ortho_box::正射影を直方体として読む);
        let 軸一覧 = [0, 1, 2].map(|番号| 直方体一覧[帯番号::帯0.添字()].軸(番号));
        Self {
            帯ごとの区間: 直方体一覧.map(|直方体| rebase::別の基底で見た区間(&直方体, &軸一覧)),
            軸一覧,
        }
    }

    /// カメラ相対空間の点を光空間へ写す。基底が正規直交であるため長さは変わらず、境界球の半径はそのまま使える。
    pub(super) fn 写す(&self, 点: [f32; 3]) -> [f32; 3] {
        self.軸一覧.map(|軸| 内積(軸, 点))
    }

    pub(super) fn 帯の区間(&self, 番号: 帯番号) -> 光空間区間 {
        self.帯ごとの区間[番号.添字()]
    }

    /// 軸に平行な包囲領域を光空間で見た区間。ある軸について、軸方向へ最も進んだ頂点と最も戻った頂点の
    /// 2つだけを見れば区間の両端が決まる。
    pub(super) fn 包囲領域の区間(&self, 最小: [f32; 3], 最大: [f32; 3]) -> 光空間区間 {
        let 軸ごと = self.軸一覧.map(|軸| {
            let 最も進んだ頂点 = [0, 1, 2].map(|成分| if 軸[成分] >= 0.0 { 最大[成分] } else { 最小[成分] });
            let 最も戻った頂点 = [0, 1, 2].map(|成分| if 軸[成分] >= 0.0 { 最小[成分] } else { 最大[成分] });
            (内積(軸, 最も戻った頂点), 内積(軸, 最も進んだ頂点))
        });
        光空間区間::生成する(軸ごと.map(|(下, _)| 下), 軸ごと.map(|(_, 上)| 上))
    }
}

fn 内積(左: [f32; 3], 右: [f32; 3]) -> f32 {
    左[0] * 右[0] + 左[1] * 右[1] + 左[2] * 右[2]
}
