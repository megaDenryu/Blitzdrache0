//! 視錐台を囲む1枚の平面。内側を正とする符号付き距離だけを外へ返す。
//! 法線の長さを1へ正規化してから保持するのは、距離の比較相手が境界球の半径というメートルの量だからである。
//! 長さが0になる退化した係数は「常に内側と答える平面」として保持する。誤って描くことは許され、誤って消すことは許されないためである。

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 視錐台平面 {
    法線: [f32; 3],
    定数: f32,
}

impl 視錐台平面 {
    /// 平面の方程式`法線・点 + 定数 = 0`の4係数から作る。内側は符号付き距離が正の側である。
    pub(super) fn 係数から生成する(係数: [f32; 4]) -> Self {
        let 長さ二乗 = 係数[0] * 係数[0] + 係数[1] * 係数[1] + 係数[2] * 係数[2];
        let 長さ = 長さ二乗.sqrt();
        if !長さ.is_finite() || 長さ <= 0.0 {
            return Self {
                法線: [0.0; 3], 定数: 0.0
            };
        }
        Self {
            法線: [係数[0] / 長さ, 係数[1] / 長さ, 係数[2] / 長さ],
            定数: 係数[3] / 長さ,
        }
    }

    pub(super) fn 符号付き距離(&self, 点: [f32; 3]) -> f32 {
        self.法線[0] * 点[0] + self.法線[1] * 点[1] + self.法線[2] * 点[2] + self.定数
    }

    pub(super) fn 法線(&self) -> [f32; 3] {
        self.法線
    }
}
