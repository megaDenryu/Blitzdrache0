//! カメラ相対フレームのビュー射影変換から導いた6枚の平面の組。
//! 平面はビュー射影の行の和差で得られる(左=行3+行0、右=行3-行0、下=行3+行1、上=行3-行1、近=行2、遠=行3-行2)。
//! 近平面が行3+行2でなく行2そのものなのは、このエンジンのクリップ空間の深度が0から1だからである
//! (参照: `crates/blitz_math/src/frame/transform_construct.rs`の透視投影)。
//! 判定はカメラ相対空間で行うため、入力のビュー射影もカメラ相対フレームのものでなければならない
//! (参照: `_doc/設計/地形とカメラ相対描画.md`「カメラ相対描画の契約」)。

use blitz_math::{クリップ, ワールド, 変換};

use super::plane::視錐台平面;

pub struct 視錐台 {
    平面一覧: [視錐台平面; 6],
}

impl 視錐台 {
    pub fn カメラ相対ビュー射影から生成する(ビュー射影: 変換<ワールド, クリップ>) -> Self {
        let 列優先 = ビュー射影.gpu境界用列優先配列();
        let 行 = |番号: usize| [列優先[0][番号], 列優先[1][番号], 列優先[2][番号], 列優先[3][番号]];
        let (行0, 行1, 行2, 行3) = (行(0), 行(1), 行(2), 行(3));
        Self {
            平面一覧: [
                視錐台平面::係数から生成する(足す(行3, 行0)),
                視錐台平面::係数から生成する(引く(行3, 行0)),
                視錐台平面::係数から生成する(足す(行3, 行1)),
                視錐台平面::係数から生成する(引く(行3, 行1)),
                視錐台平面::係数から生成する(行2),
                視錐台平面::係数から生成する(引く(行3, 行2)),
            ],
        }
    }

    pub(super) fn 平面一覧(&self) -> &[視錐台平面; 6] {
        &self.平面一覧
    }
}

fn 足す(左: [f32; 4], 右: [f32; 4]) -> [f32; 4] {
    [0, 1, 2, 3].map(|成分| 左[成分] + 右[成分])
}

fn 引く(左: [f32; 4], 右: [f32; 4]) -> [f32; 4] {
    [0, 1, 2, 3].map(|成分| 左[成分] - 右[成分])
}
