//! パス別のビット列の位置が`可視パス::添字`と一致することの検査。ビットの位置は距離区分マスク(`blitz_render`)と
//! 可視パス(同じく`blitz_render`)が別々に決めるため、その対応が崩れると数え上げも並べ替えも
//! 黙って別のパスの区間を指し、絵は変わるのに型検査は通る。全パスについて対応を固定する。

use blitz_render::cascade::{距離区分マスク, 距離区分番号};
use blitz_render::可視パス;

use super::可視パス集合;

fn 立っているか(集合: 可視パス集合, パス: 可視パス) -> bool {
    (集合.パス別ビット列() >> パス.添字()) & 1 == 1
}

#[test]
fn シーンだけ可視なら立つのはシーンのビットだけである() {
    let 集合 = 可視パス集合::判定から生成する(true, 距離区分マスク::空());
    assert!(立っているか(集合, 可視パス::シーン));
    assert!(!集合.いずれかの距離区分に可視か());
    for 番号 in 距離区分番号::全距離区分() {
        assert!(
            !立っているか(集合, 可視パス::影の距離区分(番号)),
            "距離区分{}のビットが立った",
            番号.添字()
        );
    }
}

#[test]
fn 距離区分ごとのビットがその距離区分のパスの添字と一致する() {
    for 番号 in 距離区分番号::全距離区分() {
        let 集合 = 可視パス集合::判定から生成する(false, 距離区分マスク::空().距離区分を立てる(番号));
        assert!(
            !立っているか(集合, 可視パス::シーン),
            "距離区分{}だけでシーンのビットが立った",
            番号.添字()
        );
        assert!(集合.いずれかの距離区分に可視か());
        for 他 in 距離区分番号::全距離区分() {
            let 期待 = 他.添字() == 番号.添字();
            let 実際 = 立っているか(集合, 可視パス::影の距離区分(他));
            assert_eq!(実際, 期待, "距離区分{}を立てたのに距離区分{}のパスの答えが違う", 番号.添字(), 他.添字());
        }
    }
}

#[test]
fn 全距離区分とシーンが可視なら全パスのビットが立つ() {
    let 集合 = 可視パス集合::判定から生成する(true, 距離区分マスク::全距離区分());
    assert!(集合.いずれかの距離区分に可視か());
    for パス in 可視パス::全パス() {
        assert!(立っているか(集合, パス), "{}のビットが立っていない", パス.名前());
    }
}

#[test]
fn どのパスにも可視でなければビット列は0である() {
    let 集合 = 可視パス集合::判定から生成する(false, 距離区分マスク::空());
    assert_eq!(集合.パス別ビット列(), 0);
    assert!(!集合.いずれかの距離区分に可視か());
}
