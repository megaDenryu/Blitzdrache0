//! 光空間の軸ごとの区間3つ、すなわち光基底に対して軸平行な直方体。境界球と別の区間に対する内外の判定を持つ。
//!
//! 半径をどの軸でも同じ量だけ効かせられるのは、光基底が正規直交で長さを変えないためである。正射影の半幅が
//! 軸ごとに違っても半径へ軸ごとの倍率が要らないのは、判定をクリップ空間ではなくメートルの光空間で行うことによる。
//! クリップ空間で判定すると軸ごとに半幅で割った非等方の座標になり、半径を軸ごとに割り直す必要が出る。
//!
//! 判定は保守的である。3軸すべてで区間の内側なら交わると答えるため、直方体の隅では交わらない球を内と答える。
//! 偽陽性(誤って描く)は許され、偽陰性(誤って影を消す)は許さない。

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 光空間区間 {
    最小: [f32; 3],
    最大: [f32; 3],
}

impl 光空間区間 {
    pub(super) fn 生成する(最小: [f32; 3], 最大: [f32; 3]) -> Self {
        Self { 最小, 最大 }
    }

    /// 常に内側と答える区間。方向光の正射影を読めない、あるいは読んだ結果が非有限になったときに使う
    /// (参照: `band_light_box/ortho_box.rs`の`正射影直方体::全域`)。無限大は有限の巨大値では代用しない。
    /// 半幅を狭くすれば`blitz_math`の大域ワールド位置がf32::MAXまで許すカメラ相対座標を取りこぼし、
    /// 半幅を広げて無限大に近づけると、この区間から中心や半幅を導く一般式が無限大同士を足し引きして
    /// NaNを生む。`球と交わるか`・`区間と重なるか`は有限な値との加減算・比較しかしないため、
    /// 無限大の境界を渡しても安全である。中心や半幅を導く式にはこの区間を渡してはならない。
    pub(super) fn 全域() -> Self {
        Self {
            最小: [f32::NEG_INFINITY; 3],
            最大: [f32::INFINITY; 3],
        }
    }

    /// 光空間の中心と半径で表した球がこの直方体と交わるか。各軸の区間を半径ぶん外へ広げた範囲に中心が入るかを見る。
    pub(super) fn 球と交わるか(self, 光空間の中心: [f32; 3], 半径: f32) -> bool {
        [0, 1, 2]
            .into_iter()
            .all(|軸| 光空間の中心[軸] >= self.最小[軸] - 半径 && 光空間の中心[軸] <= self.最大[軸] + 半径)
    }

    /// 別の区間と3軸すべてで重なるか。群の粗い判定が、群の包囲領域を光空間で見た区間との重なりで使う。
    pub(super) fn 区間と重なるか(self, 他: Self) -> bool {
        [0, 1, 2]
            .into_iter()
            .all(|軸| 他.最大[軸] >= self.最小[軸] && 他.最小[軸] <= self.最大[軸])
    }

    pub(super) fn 最小(self) -> [f32; 3] {
        self.最小
    }

    pub(super) fn 最大(self) -> [f32; 3] {
        self.最大
    }
}
