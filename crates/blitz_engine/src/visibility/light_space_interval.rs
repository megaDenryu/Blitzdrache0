//! 光空間の軸ごとの区間3つ、すなわち光基底に対して軸平行な直方体。境界球と別の区間に対する内外の判定を持つ。
//!
//! 半径をどの軸でも同じ量だけ効かせられるのは、光基底が正規直交で長さを変えないためである。正射影の半幅が
//! 軸ごとに違っても半径へ軸ごとの倍率が要らないのは、判定をクリップ空間ではなくメートルの光空間で行うことによる。
//! クリップ空間で判定すると軸ごとに半幅で割った非等方の座標になり、半径を軸ごとに割り直す必要が出る。
//!
//! 判定は保守的である。3軸すべてで区間の内側なら交わると答えるため、直方体の隅では交わらない球を内と答える。
//! 偽陽性(誤って描く)は許され、偽陰性(誤って影を消す)は許さない。
//!
//! `確定させる`が検証の正本である。この区間は消費者へ渡る前に2つの出口を通る:
//! `band_light_box/rebase.rs`の`別の基底で見た区間`(距離区分の区間)と`band_light_box.rs`の`包囲領域の区間`
//! (群の包囲領域を光空間で見た区間)。方向光の正射影を読む行列がどれだけ退化していても(軸が線形従属、
//! 行列の係数が極端、除算や内積の連鎖でオーバーフローする等)、あるいは群の包囲領域とカメラ相対の基準原点の
//! 平行移動がオーバーフローしても、上流のどの段で崩れたかを個別に塞ぐのではなく、実際に`球と交わるか`・
//! `区間と重なるか`が消費するこの区間そのものの形を、この2つの出口で検査する。
//! 上流(`ortho_box.rs`の`一軸を読む`・`ortho_box/range_box.rs`の`範囲内直方体::生成する`)にも早期回避の
//! 検査があるが、それらは安価な打ち切りにすぎず、正しさの根拠ではない。

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 光空間区間 {
    最小: [f32; 3],
    最大: [f32; 3],
}

impl 光空間区間 {
    pub(super) fn 生成する(最小: [f32; 3], 最大: [f32; 3]) -> Self {
        Self { 最小, 最大 }
    }

    /// 常に内側と答える区間。方向光の正射影を読めない、あるいは読んだ結果が非有限になったときに使う
    /// (参照: `band_light_box/ortho_box.rs`の`正射影直方体::全域`)。無限大は有限の巨大値では代用しない。
    /// 半幅を狭くすれば`blitz_math`の大域ワールド位置がf32::MAXまで許すカメラ相対座標を取りこぼし、
    /// 半幅を広げて無限大に近づけると、この区間から中心や半幅を導く一般式が無限大同士を足し引きして
    /// NaNを生む。`球と交わるか`・`区間と重なるか`は有限な値との加減算・比較しかしないため、
    /// 無限大の境界を渡しても安全である。中心や半幅を導く式にはこの区間を渡してはならない。
    pub(super) fn 全域() -> Self {
        Self {
            最小: [f32::NEG_INFINITY; 3],
            最大: [f32::INFINITY; 3],
        }
    }

    /// 光空間の中心と半径で表した球がこの直方体と交わるか。各軸の区間を半径ぶん外へ広げた範囲に中心が入るかを見る。
    pub(super) fn 球と交わるか(self, 光空間の中心: [f32; 3], 半径: f32) -> bool {
        [0, 1, 2]
            .into_iter()
            .all(|軸| 光空間の中心[軸] >= self.最小[軸] - 半径 && 光空間の中心[軸] <= self.最大[軸] + 半径)
    }

    /// 別の区間と3軸すべてで重なるか。群の粗い判定が、群の包囲領域を光空間で見た区間との重なりで使う。
    pub(super) fn 区間と重なるか(self, 他: Self) -> bool {
        [0, 1, 2]
            .into_iter()
            .all(|軸| 他.最大[軸] >= self.最小[軸] && 他.最小[軸] <= self.最大[軸])
    }

    pub(super) fn 最小(self) -> [f32; 3] {
        self.最小
    }

    pub(super) fn 最大(self) -> [f32; 3] {
        self.最大
    }

    /// この区間が距離区分の判定にそのまま使える形かを検査し、使えなければ全域へ倒す。光空間区間が消費者へ渡る
    /// 2つの出口(`別の基底で見た区間`が返す距離区分の区間、`包囲領域の区間`が返す群の区間)の両方がこれを通る、
    /// 検証の正本。
    ///
    /// 軸ごとに「下限が上限を超えない・下限が+∞でない・上限が-∞でない」を見る。NaNは`<=`が常に偽になる
    /// ため下限<=上限の条件で落ちる。下限だけが+∞、あるいは上限だけが-∞になった区間([+∞,+∞]や
    /// [-∞,-∞]等)は下限<=上限を通り抜けてしまうが、その区間は`球と交わるか`で常に偽を返す
    /// (`最大+半径`が+∞のとき`中心<=+∞`は真だが`最小-半径`が+∞のとき`中心>=+∞`は有限な中心に対し常に偽、
    /// という組み合わせで偽陰性になる)ため、追加の2条件で明示的に弾く。`全域()`自身が作る[-∞,+∞]は
    /// 3条件すべてを満たすため、素通りする。
    pub(super) fn 確定させる(self) -> Self {
        let 軸ごとに健全か = |軸: usize| self.最小[軸] <= self.最大[軸] && self.最小[軸] != f32::INFINITY && self.最大[軸] != f32::NEG_INFINITY;
        if [0, 1, 2].into_iter().all(軸ごとに健全か) {
            self
        } else {
            Self::全域()
        }
    }
}
