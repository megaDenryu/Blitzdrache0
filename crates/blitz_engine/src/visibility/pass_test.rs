//! 1つのパスぶんの視錐台判定。受け取るのは判定の方式と群の包囲領域とカメラ相対アンカー、返すのは個体1件ごとの内外である。
//! 群の粗い判定を構築の1回だけで済ませ、以後は個体の球判定だけを行う。
//!
//! 触れるのは方式と粗い判定の結果だけであり、群の状態も受け皿も持たない。この分離があるため、
//! シーンとシャドウは同じ規則を別々の視錐台で1回ずつ通せる。
//! 粗い判定で棄却した群でも個体ごとの走査そのものは省かない。走査の中で段の選択が同時に進むためである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」

use super::frustum::視錐台;
use super::volume_test::{包囲領域は視錐台の外か, 球は視錐台の外か};
use crate::軸平行包囲領域;

/// そのフレームに1つのパスの可視個体をどう決めるか。
pub enum 可視判定方式<'a> {
    視錐台で絞る(&'a 視錐台),
    /// 可視判定を止めた実行。全個体を可視として扱う。
    全個体を可視とする,
}

pub(super) struct パス判定<'a> {
    方式: &'a 可視判定方式<'a>,
    /// 群の包囲領域が視錐台の外だったか。外なら個体の判定を1回も行わず、全個体を不可視にする。
    群を棄却した: bool,
}

impl<'a> パス判定<'a> {
    pub(super) fn 準備する(方式: &'a 可視判定方式<'a>, 領域: 軸平行包囲領域, 基点: [f32; 3]) -> Self {
        let 群を棄却した = match 方式 {
            可視判定方式::視錐台で絞る(視錐台) => {
                包囲領域は視錐台の外か(視錐台.平面一覧(), 平行移動する(領域.最小(), 基点), 平行移動する(領域.最大(), 基点))
            }
            可視判定方式::全個体を可視とする => false,
        };
        Self { 方式, 群を棄却した }
    }

    /// このパスが個体ごとの視錐台判定を実際に行うか。視錐台で絞らない方式と、粗い判定で棄却した群では行わない。
    pub(super) fn 個体を判定するか(&self) -> bool {
        matches!(self.方式, 可視判定方式::視錐台で絞る(_)) && !self.群を棄却した
    }

    pub(super) fn 可視か(&self, 中心: [f32; 3], 半径: f32) -> bool {
        match self.方式 {
            可視判定方式::全個体を可視とする => true,
            可視判定方式::視錐台で絞る(視錐台) => !self.群を棄却した && !球は視錐台の外か(視錐台.平面一覧(), 中心, 半径),
        }
    }
}

pub(super) fn 平行移動する(座標: [f32; 3], 基点: [f32; 3]) -> [f32; 3] {
    [0, 1, 2].map(|軸| 座標[軸] + 基点[軸])
}
