//! 1つの範囲ぶんの視錐台判定。受け取るのは判定に使う視錐台と群の包囲領域とカメラ相対の基準原点、返すのは個体1件ごとの内外である。
//! 群の粗い判定を構築の1回だけで済ませ、以後は個体の球判定だけを行う。
//!
//! 触れるのは視錐台と粗い判定の結果だけであり、群の状態も受け皿も持たない。影の側は同じ規則を
//! 平面でなく光空間の区間で行うため、この型はシーンパス専用である(参照: `band_pass_test.rs`)。
//! 粗い判定で棄却した群でも個体ごとの走査そのものは省かない。走査の中で段の選択が同時に進むためである。
//! `パス判定`の`群を棄却した`が真なら個体ごとの視錐台判定を1回も行わず、全個体を不可視にする。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」

use super::frustum::視錐台;
use super::volume_test::{包囲領域は視錐台の外か, 球は視錐台の外か};
use crate::軸平行包囲領域;

/// そのフレームにシーンパスの可視個体をどう決めるか。
pub enum 可視判定方式<'a> {
    視錐台で絞る(&'a 視錐台),
    全個体を可視とする, // 可視判定を止めた実行。全個体を可視として扱う
}

impl<'a> 可視判定方式<'a> {
    /// 絞る視錐台。`None`は可視判定を止めた実行である。
    pub(super) fn 視錐台(&self) -> Option<&'a 視錐台> {
        match self {
            Self::視錐台で絞る(視錐台) => Some(視錐台),
            Self::全個体を可視とする => None,
        }
    }
}

pub(super) struct パス判定<'a> {
    視錐台: Option<&'a 視錐台>, // `None`のときは全個体を可視として扱う
    群を棄却した: bool, // 群の包囲領域が視錐台の外だったか
}

impl<'a> パス判定<'a> {
    pub(super) fn 準備する(視錐台: Option<&'a 視錐台>, 領域: 軸平行包囲領域, 基点: [f32; 3]) -> Self {
        let 群を棄却した = 視錐台.is_some_and(|視錐台| {
            包囲領域は視錐台の外か(視錐台.平面一覧(), 平行移動する(領域.最小(), 基点), 平行移動する(領域.最大(), 基点))
        });
        Self {
            視錐台, 群を棄却した
        }
    }

    /// この範囲が個体ごとの視錐台判定を行うか。視錐台で絞らない方式と、粗い判定で棄却した群では行わない。
    pub(super) fn 個体を判定するか(&self) -> bool {
        self.視錐台.is_some() && !self.群を棄却した
    }

    pub(super) fn 可視か(&self, 中心: [f32; 3], 半径: f32) -> bool {
        match self.視錐台 {
            None => true,
            Some(視錐台) => !self.群を棄却した && !球は視錐台の外か(視錐台.平面一覧(), 中心, 半径),
        }
    }
}

pub(super) fn 平行移動する(座標: [f32; 3], 基点: [f32; 3]) -> [f32; 3] {
    [0, 1, 2].map(|軸| 座標[軸] + 基点[軸])
}
