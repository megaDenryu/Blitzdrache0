//! 軸平行な包囲領域を変換で写す工程。受け取るのは群のローカル空間の包囲領域と変換、返すのは基準原点からの相対の包囲領域である。
//! 8つの頂点をすべて写してから軸ごとの最小と最大を取る。回転が入ると軸平行のままでは写せないが、
//! 写した8点を覆う軸平行領域は元の領域を必ず含むため、粗い判定の保守性が保たれる。

use blitz_math::{メートル, ローカル, ワールド, 位置, 変換};

use crate::軸平行包囲領域;

pub(super) fn 包囲領域を写す(
    領域: 軸平行包囲領域, ローカルからワールド: 変換<ローカル, ワールド>
) -> 軸平行包囲領域 {
    let (元の最小, 元の最大) = (領域.最小(), 領域.最大());
    let mut 最小 = [f32::INFINITY; 3];
    let mut 最大 = [f32::NEG_INFINITY; 3];
    for 頂点番号 in 0..8 {
        let 頂点 = [0, 1, 2].map(|軸| {
            if 頂点番号 & (1 << 軸) == 0 {
                元の最小[軸]
            } else {
                元の最大[軸]
            }
        });
        let 写した点 = ローカルからワールド.適用する(位置::<ローカル>::生成する(
            メートル::生成する(頂点[0]),
            メートル::生成する(頂点[1]),
            メートル::生成する(頂点[2]),
        ));
        let 成分 = [写した点.x().値(), 写した点.y().値(), 写した点.z().値()];
        for 軸 in 0..3 {
            最小[軸] = 最小[軸].min(成分[軸]);
            最大[軸] = 最大[軸].max(成分[軸]);
        }
    }
    match 軸平行包囲領域::生成する(最小, 最大) {
        Ok(値) => 値,
        Err(_) => panic!("写した8頂点から作る包囲領域は最小が最大を上回らないという不変条件に違反した"),
    }
}
