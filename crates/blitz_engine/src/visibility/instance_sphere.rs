//! 個体1件を覆う境界球。原型の境界球を個体の配置で写したものであり、チャンクアンカー基準の座標で持つ。
//! スケールは3成分の最大値を半径へ掛ける。軸ごとに違う倍率でも球が個体を覆い続けるためであり、
//! 半径を小さく見積もると画面内の個体を消しうる。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」

use blitz_math::{メートル, ローカル, 位置};

use crate::{個体配置, 境界球};

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 個体境界球 {
    中心: 位置<ローカル>,
    半径: メートル,
}

impl 個体境界球 {
    pub fn 生成する(中心: 位置<ローカル>, 半径: メートル) -> Self {
        Self { 中心, 半径 }
    }

    pub fn 配置で写す(原型の境界球: 境界球, 配置: &個体配置) -> Self {
        let 元の中心 = 原型の境界球.中心();
        let 局所中心 = 位置::生成する(
            メートル::生成する(元の中心[0]),
            メートル::生成する(元の中心[1]),
            メートル::生成する(元の中心[2]),
        );
        let 倍率 = 配置.スケール().into_iter().map(f32::abs).fold(0.0_f32, f32::max);
        Self {
            中心: 配置.変換を作る().適用する(局所中心),
            半径: メートル::生成する(原型の境界球.半径() * 倍率),
        }
    }

    pub fn 中心(&self) -> 位置<ローカル> {
        self.中心
    }

    pub fn 半径(&self) -> メートル {
        self.半径
    }

    pub(super) fn 中心成分(&self) -> [f32; 3] {
        [self.中心.x().値(), self.中心.y().値(), self.中心.z().値()]
    }

    pub(super) fn 半径値(&self) -> f32 {
        self.半径.値()
    }
}
