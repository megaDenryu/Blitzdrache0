//! 個体1件を覆う境界球。原型の境界球を、その個体のアンカー基準の変換で写したものである。
//! 空間をワールドと呼ぶのは、描画対象素材の個体変換列と同じ「カメラ相対アンカーを足す前の座標」だからであり、
//! シェーダーがこの座標へアンカーを足して相対フレームの位置を作る(参照: `_doc/設計/地形とカメラ相対描画.md`「カメラ相対描画の契約」)。
//!
//! 半径の倍率は、変換が単位長の3軸を写した長さの最大値である。回転と軸ごとのスケールを合成した変換ではこれが写った球の
//! 最大半径そのものになる。
//! 前提: 個体の変換はせん断を含まない(回転と軸スケールの合成である)。せん断を含む変換ではこの倍率が半径を過小に見積もる。

use blitz_math::{メートル, ローカル, ワールド, 位置, 変換};

use crate::境界球;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 個体境界球 {
    中心: 位置<ワールド>,
    半径: メートル,
}

impl 個体境界球 {
    pub fn 生成する(中心: 位置<ワールド>, 半径: メートル) -> Self {
        Self { 中心, 半径 }
    }

    pub fn 変換で写す(原型の境界球: 境界球, ローカルからワールド: 変換<ローカル, ワールド>) -> Self {
        let 元の中心 = 原型の境界球.中心();
        let 中心 = ローカルからワールド.適用する(局所位置(元の中心));
        let 半径 = 原型の境界球.半径();
        let 倍率 = [0, 1, 2]
            .map(|軸| {
                let 軸上の点 = 局所位置(軸方向へ進めた点(元の中心, 軸, 半径));
                距離(ローカルからワールド.適用する(軸上の点), 中心)
            })
            .into_iter()
            .fold(0.0_f32, f32::max);
        Self {
            中心,
            半径: メートル::生成する(倍率),
        }
    }

    pub fn 中心(&self) -> 位置<ワールド> {
        self.中心
    }

    pub fn 半径(&self) -> メートル {
        self.半径
    }

    pub(super) fn 中心成分(&self) -> [f32; 3] {
        [self.中心.x().値(), self.中心.y().値(), self.中心.z().値()]
    }

    pub(super) fn 半径値(&self) -> f32 {
        self.半径.値()
    }
}

fn 局所位置(成分: [f32; 3]) -> 位置<ローカル> {
    位置::生成する(メートル::生成する(成分[0]), メートル::生成する(成分[1]), メートル::生成する(成分[2]))
}

fn 軸方向へ進めた点(中心: [f32; 3], 軸: usize, 距離: f32) -> [f32; 3] {
    let mut 点 = 中心;
    点[軸] += 距離;
    点
}

fn 距離(点: 位置<ワールド>, 中心: 位置<ワールド>) -> f32 {
    let 差 = [点.x().値() - 中心.x().値(), 点.y().値() - 中心.y().値(), 点.z().値() - 中心.z().値()];
    (差[0] * 差[0] + 差[1] * 差[1] + 差[2] * 差[2]).sqrt()
}
