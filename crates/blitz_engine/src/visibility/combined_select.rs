//! 可視判定と段選択を同じ1回の走査で行う工程。受け取るのは判定の方式と群の材料とカメラ相対アンカーと段の方式、
//! 書き出すのは段別の並びのID列と段の範囲である。
//!
//! 群の包囲領域による粗い判定は個体ごとの視錐台判定を省くが、走査そのものは省かない。
//! シャドウパスがカメラ視錐台の外の個体も描き、その段もカメラ距離で決まるためである。
//! 粗い判定で棄却した群は個体判定数が0になり、そのことが2段階判定が効いていることの計数側の証拠になる。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」「個体別LOD」

use blitz_math::{カメラ相対位置, メートル};

use super::count::可視判定計数;
use super::frustum::視錐台;
use super::group_material::群可視材料;
use super::stage_tray::段別ID受け皿;
use super::volume_test::{包囲領域は視錐台の外か, 球は視錐台の外か};
use crate::{個体LOD選択設定, 個体別段状態};

/// そのフレームにシーンパスの可視個体をどう決めるか。
pub enum 可視判定方式<'a> {
    視錐台で絞る(&'a 視錐台),
    /// 可視判定を止めた実行。全個体を可視として扱い、段の選択だけを行う。
    全個体を可視とする,
}

/// そのフレームに個体の段をどう決めるか。
#[derive(Clone, Copy)]
pub enum 段選択方式 {
    距離とヒステリシス(個体LOD選択設定),
    /// 個体別LODを止めた実行。全個体を最詳細段で描く。
    最詳細に固定,
}

pub struct 個体選択材料<'a> {
    pub 可視判定: 可視判定方式<'a>,
    pub 材料: &'a 群可視材料,
    /// この群を所有するチャンクの描画アンカーからカメラ大域原点を引いた値。材料の座標はアンカー基準のため、
    /// これを足した位置がカメラ相対空間の位置になり、その長さがそのままカメラからの距離になる。
    pub カメラ相対アンカー: カメラ相対位置,
    pub 段選択: 段選択方式,
}

pub fn 可視個体と段を選ぶ(
    材料: &個体選択材料<'_>, 状態: &mut 個体別段状態, 受け皿: &mut 段別ID受け皿
) -> 可視判定計数 {
    let 基点 = [
        材料.カメラ相対アンカー.x().値(),
        材料.カメラ相対アンカー.y().値(),
        材料.カメラ相対アンカー.z().値(),
    ];
    let 候補数 = 材料.材料.個体数();
    let 個体を判定するか = !群を粗く棄却するか(材料, 基点);
    受け皿.群を始める(状態.段数());
    for (添字, 球) in 材料.材料.個体境界球一覧().iter().enumerate() {
        let 中心 = 平行移動する(球.中心成分(), 基点);
        let 段 = 段を決める(材料.段選択, 状態, 添字, 中心);
        let 可視 = 個体を判定するか && 個体は可視か(&材料.可視判定, 中心, 球.半径値());
        受け皿.個体を積む(段.番号(), 可視);
    }
    let 可視数 = 受け皿.群を書き出す();
    if 個体を判定するか {
        可視判定計数::個体を判定した(候補数, 可視数)
    } else {
        可視判定計数::群を棄却した(候補数)
    }
}

fn 群を粗く棄却するか(材料: &個体選択材料<'_>, 基点: [f32; 3]) -> bool {
    let 可視判定方式::視錐台で絞る(視錐台) = 材料.可視判定 else {
        return false;
    };
    let 領域 = 材料.材料.群の包囲領域();
    包囲領域は視錐台の外か(視錐台.平面一覧(), 平行移動する(領域.最小(), 基点), 平行移動する(領域.最大(), 基点))
}

fn 個体は可視か(可視判定: &可視判定方式<'_>, 中心: [f32; 3], 半径: f32) -> bool {
    match 可視判定 {
        可視判定方式::視錐台で絞る(視錐台) => !球は視錐台の外か(視錐台.平面一覧(), 中心, 半径),
        可視判定方式::全個体を可視とする => true,
    }
}

/// 個体の段。カメラ相対空間では視点が原点にあるため、境界球の中心の長さがそのままカメラからの距離である。
fn 段を決める(方式: 段選択方式, 状態: &mut 個体別段状態, 添字: usize, 中心: [f32; 3]) -> crate::個体詳細段 {
    match 方式 {
        段選択方式::距離とヒステリシス(設定) => 状態.段を決める(添字, メートル::生成する(長さ(中心)), 設定),
        段選択方式::最詳細に固定 => crate::個体詳細段::最詳細(),
    }
}

fn 長さ(座標: [f32; 3]) -> f32 {
    (座標[0] * 座標[0] + 座標[1] * 座標[1] + 座標[2] * 座標[2]).sqrt()
}

fn 平行移動する(座標: [f32; 3], 基点: [f32; 3]) -> [f32; 3] {
    [0, 1, 2].map(|軸| 座標[軸] + 基点[軸])
}
