//! 可視判定と段選択を同じ1回の走査で行う工程。受け取るのはシーンと距離区分別の判定方式と群の材料とカメラ相対の基準原点と段の方式、
//! 書き出すのはパス別・段別の並びのID列と段のパス別区間である。
//!
//! シーンと距離区分0から距離区分3はそれぞれの視錐台で別々に判定する。カメラ視錐台で絞った可視集合を影へ流用してはならず、
//! 画面外の個体が画面内へ影を落とすためである。すべての判定を同じ走査へ入れるのは、どれも同じ個体の同じ境界球を読み、
//! 分けると走査がパス数ぶんの周回になるからである。
//!
//! 群の包囲領域による粗い判定は個体ごとの視錐台判定を省くが、走査そのものは省かない。個体の段がカメラ距離で決まり、
//! 群がどちらのパスから見えなくても段の記憶は進めるためである。
//! 粗い判定で両パスとも棄却した群は個体判定数が0になり、そのことが2段階判定が効いていることの計数側の証拠になる。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」「個体別LOD」

use blitz_math::{カメラ相対位置, メートル};

use super::band_pass_test::距離区分別の判定;
use super::band_visibility_mode::距離区分別の可視判定;
use super::camera_distance::{カメラからの距離, 基点にする};
use super::count::可視判定計数;
use super::group_material::群可視材料;
use super::pass_test::{パス判定, 可視判定方式, 平行移動する};
use super::selector::可視個体と段の選別係;
use super::visible_pass_set::可視パス集合;
use crate::{個体LOD選択設定, 個体別段状態};

/// そのフレームに個体の段をどう決めるか。
#[derive(Clone, Copy)]
pub enum 段選択方式 {
    距離とヒステリシス(個体LOD選択設定),
    /// 個体別LODを止めた実行。全個体を最詳細段で描く。
    最詳細に固定,
}

pub struct 個体選択材料<'a> {
    /// シーンパスの可視個体を決める方式。カメラ相対フレームのカメラ視錐台を渡す。
    pub シーン可視判定: 可視判定方式<'a>,
    /// 距離区分ごとの影の可視個体を決める方式。同じフレームの距離区分ごとのライトビュー射影から導いた4つの視錐台を渡す。
    pub 距離区分別の可視判定: 距離区分別の可視判定<'a>,
    pub 材料: &'a 群可視材料,
    /// この群を所有するチャンクの描画の基準原点からカメラ大域原点を引いた値。材料の座標は基準原点からの相対のため、
    /// これを足した位置がカメラ相対空間の位置になり、その長さがそのままカメラからの距離になる。
    pub カメラ相対の基準原点: カメラ相対位置,
    pub 段選択: 段選択方式,
}

impl 可視個体と段の選別係 {
    /// 群1つの可視個体と段を選び、その群のID列と段のパス別区間を自分の列の末尾へ連ねる。
    /// 段の記憶は群ごとに1つあるため、その群の登録を持つ側から借りて受け取る。
    pub fn 群1つの可視個体と段を選ぶ(
        &mut self, 材料: &個体選択材料<'_>, 段の記憶: &mut 個体別段状態
    ) -> 可視判定計数 {
        let 基点 = 基点にする(材料.カメラ相対の基準原点);
        let 領域 = 材料.材料.群の包囲領域();
        let シーン = パス判定::準備する(材料.シーン可視判定.視錐台(), 領域, 基点);
        let 距離区分別 = 距離区分別の判定::準備する(&材料.距離区分別の可視判定, 領域, 基点);
        let 個体を判定したか = シーン.個体を判定するか() || 距離区分別.個体を判定するか();
        let 候補数 = 材料.材料.個体数();
        self.段別.群を始める(段の記憶.段数());
        for (添字, 球) in 材料.材料.個体境界球一覧().iter().enumerate() {
            let 中心 = 平行移動する(球.中心成分(), 基点);
            let 距離 = カメラからの距離(中心);
            let 段 = 段を決める(材料.段選択, 段の記憶, 添字, 距離);
            let 半径 = 球.半径値();
            let 可視 = 可視パス集合::判定から生成する(シーン.可視か(中心, 半径), 距離区分別.個体のマスク(中心, 半径, 距離));
            self.段別.個体を積む(段.番号(), 可視);
        }
        可視判定計数::生成する(候補数, 個体を判定したか, self.段別.群を書き出す())
    }
}

fn 段を決める(
    方式: 段選択方式, 状態: &mut 個体別段状態, 添字: usize, カメラからの距離: メートル
) -> crate::個体詳細段 {
    match 方式 {
        段選択方式::距離とヒステリシス(設定) => 状態.段を決める(添字, カメラからの距離, 設定),
        段選択方式::最詳細に固定 => crate::個体詳細段::最詳細(),
    }
}
