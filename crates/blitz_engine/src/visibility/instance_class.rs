//! 1個体が2つのパスに対して取る可視の組み合わせ。シーンとシャドウは別々の視錐台で判定するため、
//! 個体は「どちらにも見える」「片方だけに見える」「どちらにも見えない」の4通りのどれかになる。
//! 2つの真偽値の対でなく1つの列挙で持つのは、可視ID列の並べ替えがこの4通りをそのまま区分の番号として使い、
//! 組み合わせの取りこぼしを網羅的な照合で防ぐためである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「描画発行」

/// 区分の並び順そのものが可視ID列の中の並び順である。シーンの可視個体が先頭2区分、シャドウの可視個体が中央2区分を
/// 占めるため、どちらのパスも1つの連続範囲で描ける。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 個体区分 {
    シーンのみ可視,
    両方可視,
    シャドウのみ可視,
    どちらも不可視,
}

/// 区分の総数。並べ替えの集計が段ごとに持つ列の長さである。
pub(super) const 区分の数: usize = 4;

impl 個体区分 {
    pub(super) fn 判定から決める(シーン可視: bool, シャドウ可視: bool) -> Self {
        match (シーン可視, シャドウ可視) {
            (true, false) => Self::シーンのみ可視,
            (true, true) => Self::両方可視,
            (false, true) => Self::シャドウのみ可視,
            (false, false) => Self::どちらも不可視,
        }
    }

    pub(super) fn 添字(self) -> usize {
        match self {
            Self::シーンのみ可視 => 0,
            Self::両方可視 => 1,
            Self::シャドウのみ可視 => 2,
            Self::どちらも不可視 => 3,
        }
    }

    pub(super) fn シーン可視か(self) -> bool {
        matches!(self, Self::シーンのみ可視 | Self::両方可視)
    }

    pub(super) fn シャドウ可視か(self) -> bool {
        matches!(self, Self::両方可視 | Self::シャドウのみ可視)
    }
}
