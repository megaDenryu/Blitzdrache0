//! 距離を帯へ振り分ける規則の固定。帯の境界と最後の帯の受け皿としての振る舞いを検査する。
//! 境界をここで固定するのは、報告の帯番号から距離を読み戻す側(裁定の水準の導出)が帯の下限を
//! 「番号×帯の幅」として計算するためであり、振り分けがその式とずれると導いた距離が意味を失うためである。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;
use blitz_render::cascade::{距離区分マスク, 距離区分番号};

use super::{キャスター距離分布, 帯の幅, 帯の数, 帯番号};

#[test]
fn 帯の下限はその帯へ入り上限は次の帯へ入る() {
    assert_eq!(帯番号(メートル::生成する(0.0)), 0);
    assert_eq!(帯番号(メートル::生成する(帯の幅 - 0.001)), 0);
    assert_eq!(帯番号(メートル::生成する(帯の幅)), 1);
    assert_eq!(帯番号(メートル::生成する(帯の幅 * 2.0)), 2);
}

/// 最後の帯は上限を持たず、それより遠い個体をすべて受ける。
#[test]
fn 最後の帯は上限を持たない() {
    let 最終番号 = 帯の数 - 1;
    assert_eq!(帯番号(メートル::生成する(帯の幅 * 16.0)), 最終番号);
    assert_eq!(帯番号(メートル::生成する(100_000.0)), 最終番号);
}

#[test]
fn 距離区分別と和集合を別々に数える() {
    let mut 分布 = キャスター距離分布::default();
    let 距離区分1と2 = 距離区分マスク::空()
        .距離区分を立てる(距離区分番号::距離区分1)
        .距離区分を立てる(距離区分番号::距離区分2);
    分布.個体を積む(メートル::生成する(10.0), 距離区分1と2);
    分布.個体を積む(メートル::生成する(10.0), 距離区分マスク::空());
    assert_eq!(分布.帯別の候補数()[0], 2);
    assert_eq!(分布.帯別の和集合の可視数()[0], 1);
    assert_eq!(分布.帯別の距離区分別の可視数()[1][0], 1);
    assert_eq!(分布.帯別の距離区分別の可視数()[2][0], 1);
    assert_eq!(分布.帯別の距離区分別の可視数()[0][0], 0);
}
