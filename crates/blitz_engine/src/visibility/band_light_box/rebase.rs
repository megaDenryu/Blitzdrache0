//! ある軸で表した直方体を、別の軸で見た区間へ写す工程。受け取るのは直方体と共有する光基底、
//! 返すのはその基底の軸ごとの区間である。
//!
//! 4帯の正射影は同じ方向光を同じ上方向で見下ろすため、基底は数学的には一致する。しかし行列は帯ごとに別々の
//! 注視から組み立てられるため、正規化の丸めで軸が最下位ビットの桁だけ食い違う。共有基底で見た区間は
//! その食い違いを含めて直方体を覆わなければならないため、直方体を「共有基底に対してわずかに傾いた箱」として扱い、
//! 軸ごとの投影の幅を取る。傾きの投影は幅を広げる方向にも狭める方向にも働くため、丸めの桁を上回る余裕を足して
//! 必ず外へ広げる。区間が内側へわずかに縮むと影が欠けるが、外へ広がっても絵は変わらない
//! (帯の外の個体はGPUの側で必ずクリップされ、シャドウマップに1画素も書かない)。
//!
//! 全域(方向光の正射影を読めなかった腕)はこの投影を経由しない。中心・半幅を導く一般式に無限大を渡すと
//! NaNになるため(参照: `ortho_box.rs`)、`光空間区間::全域()`をそのまま返す。

use super::super::light_space_interval::光空間区間;
use super::ortho_box::正射影直方体;
use super::内積;

/// 区間へ足す余裕の、直方体の大きさに対する割合。f32の相対丸めは1e-7の桁であるため、正規化と内積の
/// 丸めが重なっても足りるように1桁の余裕を置く。500メートルの帯に対して0.5ミリメートルであり、
/// シャドウマップの1テクセルが覆う長さより4桁小さい。
const 相対余裕: f32 = 1e-6;

pub(super) fn 別の基底で見た区間(直方体: &正射影直方体, 基底: &[[f32; 3]; 3]) -> 光空間区間 {
    let 範囲内 = match 直方体 {
        正射影直方体::全域 => return 光空間区間::全域(),
        正射影直方体::範囲内(直方体) => 直方体,
    };
    let 中心 = 範囲内.中心();
    let 半幅 = 範囲内.半幅();
    let 余裕 = 相対余裕 * (成分の和(中心) + 成分の和(半幅));
    let 軸ごと = 基底.map(|軸| {
        let 位置 = 内積(軸, 中心);
        let 幅: f32 = (0..3).map(|番号| 半幅[番号] * 内積(軸, 範囲内.軸(番号)).abs()).sum();
        (位置 - 幅 - 余裕, 位置 + 幅 + 余裕)
    });
    光空間区間::生成する(軸ごと.map(|(下, _)| 下), 軸ごと.map(|(_, 上)| 上))
}

/// 大きさの目安として使う成分の絶対値の和。丸めの誤差は成分の大きさに比例するため、2乗和の平方根でなく
/// 上界になる和で取る。
fn 成分の和(成分: [f32; 3]) -> f32 {
    成分[0].abs() + 成分[1].abs() + 成分[2].abs()
}
