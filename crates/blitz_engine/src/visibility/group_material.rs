//! 1つのインスタンス群を毎フレーム判定するために、束の読込時に一度だけ作る材料。
//! 群の包囲領域と、個体ごとに写し終えた境界球の列を、どちらも基準原点からの相対の座標で持つ。
//! 個体の境界球を毎フレーム配置から写し直さないのは、配置が読込後に変わらず、写す計算がフレームごとに同じ結果を返す重複計算になるためである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」

use blitz_math::{ローカル, ワールド, 変換};

use super::bounds_transform::包囲領域を写す;
use super::error::可視判定エラー;
use super::instance_sphere::個体境界球;
use crate::{インスタンス群, 軸平行包囲領域};

pub struct 群可視材料 {
    群の包囲領域: 軸平行包囲領域,
    個体境界球一覧: Vec<個体境界球>,
}

impl 群可視材料 {
    /// 個体数の上限をここで確かめることが、判定の側が添字をu32へ変換できるという不変条件の根拠になる。
    pub fn 生成する(
        群の包囲領域: 軸平行包囲領域, 個体境界球一覧: Vec<個体境界球>
    ) -> Result<Self, 可視判定エラー> {
        if u32::try_from(個体境界球一覧.len()).is_err() {
            return Err(可視判定エラー::個体数過大 {
                個体数: 個体境界球一覧.len(),
            });
        }
        Ok(Self {
            群の包囲領域,
            個体境界球一覧,
        })
    }

    /// `ローカルからワールド`は、その描画対象が基準原点からの相対で持つ静的な変換である。群が焼いた境界は原型と配置だけで
    /// 決まる群のローカル空間にあるため、描画と同じ座標で判定するにはこの変換を通す必要がある。
    pub fn 群から生成する(
        群: &インスタンス群, ローカルからワールド: 変換<ローカル, ワールド>
    ) -> Result<Self, 可視判定エラー> {
        let 原型の境界球 = 群.境界().原型の境界球();
        let 個体境界球一覧 = 群
            .配置一覧()
            .iter()
            .map(|配置| 個体境界球::変換で写す(原型の境界球, 配置.変換を作る().合成する(ローカルからワールド)))
            .collect();
        Self::生成する(包囲領域を写す(群.境界().群の包囲領域(), ローカルからワールド), 個体境界球一覧)
    }

    pub fn 個体数(&self) -> usize {
        self.個体境界球一覧.len()
    }

    pub(super) fn 群の包囲領域(&self) -> 軸平行包囲領域 {
        self.群の包囲領域
    }

    pub(super) fn 個体境界球一覧(&self) -> &[個体境界球] {
        &self.個体境界球一覧
    }
}
