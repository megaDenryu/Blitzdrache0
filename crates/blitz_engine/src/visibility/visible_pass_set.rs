//! 1個体がどのパスから見えるかの集合。シーンパスの真偽と、影を落とす距離区分のマスクの組である。
//! 4区分の列挙(シーンのみ・両方・シャドウのみ・不可視)を置き換えた型であり、シャドウ側が1つでなく4つの距離区分になったため、
//! 取りうる組み合わせが2の5乗へ増えて列挙では表せなくなったことによる。
//! 1個体が複数の距離区分へ同時に所属しうることは欠陥ではなく、正しい影に必要である
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」)。

use blitz_render::cascade::距離区分マスク;
use blitz_render::可視パス;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 可視パス集合 {
    シーン可視: bool,
    距離区分マスク: 距離区分マスク,
}

impl 可視パス集合 {
    pub(super) fn 判定から生成する(シーン可視: bool, 距離区分マスク: 距離区分マスク) -> Self {
        Self {
            シーン可視, 距離区分マスク
        }
    }

    /// そのパスの区間へこの個体を積むか。並べ替えはこの答えだけを見てパスごとの区間へ個体IDを書く。
    pub(super) fn パスに可視か(self, パス: 可視パス) -> bool {
        match パス {
            可視パス::シーン => self.シーン可視,
            可視パス::影の距離区分(番号) => self.距離区分マスク.立っているか(番号),
        }
    }

    pub(super) fn シーン可視か(self) -> bool {
        self.シーン可視
    }

    /// 1つ以上の距離区分へ影を落とすか。距離区分別の可視数を足すと複数の距離区分に属する個体を重複して数えるため、
    /// 「影を落とす個体が1体も落ちていない」ことは距離区分の和でなくこの真偽の数で見る。
    pub(super) fn いずれかの距離区分に可視か(self) -> bool {
        !self.距離区分マスク.空か()
    }
}
