//! 1個体がどのパスから見えるかの集合。可視ID列のパスの正典順(シーン→距離区分0から距離区分3)と同じ位置へ
//! ビットを立てた1本のビット列で持つ。シーンの真偽と距離区分マスクの組で持っていた形の後継であり、
//! 数え上げと並べ替えが1個体につきパス5本を列挙して同じ述語を評価し直していたのをビット演算へ替えるために置く。
//!
//! 1個体が複数の距離区分へ同時に所属しうることは欠陥ではなく、正しい影に必要である
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」)。
//!
//! 注意: ビットの位置は`可視パス::添字`と一致していなければならない。距離区分マスクのビットの位置は
//! 距離区分番号の添字であり、シーンパスが正典順の先頭を占めるため`影のビット開始`ぶん左へずらして重ねる。
//! 2つの型が別々に決めた位置が食い違うと、数え上げも並べ替えも黙って別のパスの区間を指す。
//! この対応は`mask_tests`が全パスについて固定する。

#[cfg(test)]
mod mask_tests;

use blitz_render::cascade::{距離区分マスク, 距離区分数};
use blitz_render::可視ID列を読むパス数;

/// 影の距離区分のビットが始まる位置。シーンパスが正典順の先頭に占める本数である。
const 影のビット開始: usize = 可視ID列を読むパス数 - 距離区分数;

/// 影の距離区分ぶんのビットをすべて立てた値。いずれかの距離区分に可視かを1回の論理積で見るために持つ。
const 影のビット群: u8 = ((1u8 << 距離区分数) - 1) << 影のビット開始;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 可視パス集合 {
    パス別ビット列: u8,
}

impl 可視パス集合 {
    pub(super) fn 判定から生成する(シーン可視: bool, 距離区分マスク: 距離区分マスク) -> Self {
        Self {
            パス別ビット列: u8::from(シーン可視) | (距離区分マスク.ビット列() << 影のビット開始),
        }
    }

    /// パスの正典順にビットが並んだ値。数え上げも並べ替えもこの値だけを読み、パスの列挙を個体ごとに回さない。
    pub(super) fn パス別ビット列(self) -> u8 {
        self.パス別ビット列
    }

    /// 1つ以上の距離区分へ影を落とすか。距離区分別の可視数を足すと複数の距離区分に属する個体を重複して数えるため、
    /// 「影を落とす個体が1体も落ちていない」ことは距離区分の和でなくこの真偽の数で見る。
    pub(super) fn いずれかの距離区分に可視か(self) -> bool {
        self.パス別ビット列 & 影のビット群 != 0
    }
}
