//! カメラ相対空間で個体の中心がカメラからどれだけ離れているか。担当するのは、群の材料が持つ座標を
//! カメラ相対空間へ移す基点を作ることと、その空間の中心からカメラまでの距離を返すことである。
//!
//! カメラ相対空間では視点が原点にあるため、中心の長さがそのままカメラからの距離になる。
//! 規則をここへ置くのは、個体別LODの段を決める走査とキャスターの距離分布を数える走査が同じ距離を読むためであり、
//! 2つが別々に長さを組み立てると片方だけが基点を足し忘れても気づけないためである。

use blitz_math::{カメラ相対位置, メートル};

/// 群の材料の座標へ足すとカメラ相対空間の位置になる基点。材料の座標はその群を所有するチャンクの描画の基準原点からの相対であり、
/// カメラ大域原点を引いた基準原点を足すことでカメラ相対空間へ移る。
pub(super) fn 基点にする(カメラ相対の基準原点: カメラ相対位置) -> [f32; 3] {
    [
        カメラ相対の基準原点.x().値(),
        カメラ相対の基準原点.y().値(),
        カメラ相対の基準原点.z().値(),
    ]
}

pub(super) fn カメラからの距離(中心: [f32; 3]) -> メートル {
    メートル::生成する((中心[0] * 中心[0] + 中心[1] * 中心[1] + 中心[2] * 中心[2]).sqrt())
}
