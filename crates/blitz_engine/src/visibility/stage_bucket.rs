//! 群1つぶんの判定を、LOD段ごとの連続範囲へ並べ替える工程。受け取るのは個体ごとの(段番号, 区分)の並び、
//! 書き出すのは段ごとに連続し、段の内側が4区分の順に並んだID列と、段ごとの範囲である。
//!
//! 段の内側を`[シーンのみ可視][両方可視][シャドウのみ可視][どちらも不可視]`の順に置くのは、
//! 交差する2つの可視集合を1本の列の中の連続範囲2つで表すためである。列をパスごとに2本へ分けると、
//! 個体数ぶんのホスト可視メモリと毎フレームの書き込み量がどちらも2倍になる
//! (参照: `_doc/設計/植生インスタンスと物量計測.md`「描画発行」)。
//!
//! 作業領域を型が持ち続けるのは、群ごとに列を確保して捨てることを毎フレーム繰り返さないためである。
//! 段ごとに数える4区分の件数と書込位置は`tally`が持つ。

mod tally;

use blitz_render::段別描画範囲;

use super::instance_class::個体区分;
use tally::段別集計;

#[derive(Clone, Copy)]
struct 個体判定 {
    段番号: u8,
    区分: 個体区分,
}

#[derive(Default)]
pub(super) struct 段別並べ替え {
    個体別判定: Vec<個体判定>,
    シーン可視数: usize,
    シャドウ可視数: usize,
    集計: 段別集計,
}

impl 段別並べ替え {
    pub(super) fn 群を始める(&mut self, 段数: usize) {
        self.個体別判定.clear();
        self.シーン可視数 = 0;
        self.シャドウ可視数 = 0;
        self.集計.群を始める(段数);
    }

    pub(super) fn 個体を積む(&mut self, 段番号: u8, 区分: 個体区分) {
        self.集計.個体を数える(usize::from(段番号), 区分);
        self.シーン可視数 += usize::from(区分.シーン可視か());
        self.シャドウ可視数 += usize::from(区分.シャドウ可視か());
        self.個体別判定.push(個体判定 { 段番号, 区分 });
    }

    /// 積んだ判定のパス別の可視数。書き出しの前後で変わらないため、書き出しと同じ走査で数え直さない。
    pub(super) fn パス別可視数(&self) -> (usize, usize) {
        (self.シーン可視数, self.シャドウ可視数)
    }

    pub(super) fn 書き出す(&mut self, id列: &mut Vec<u32>, 段範囲列: &mut Vec<段別描画範囲>) {
        let 基準 = id列.len();
        id列.resize(基準 + self.個体別判定.len(), 0);
        let mut 開始 = 0u32;
        for 段番号 in 0..self.集計.段数() {
            let 範囲 = self.集計.段の範囲を据える(段番号, 開始);
            開始 += 範囲.個体数();
            段範囲列.push(範囲);
        }
        for (添字, 判定) in self.個体別判定.iter().enumerate() {
            let 位置 = self.集計.書込位置を取り出して進める(usize::from(判定.段番号), 判定.区分);
            let 書込先 = 基準 + 数へ変換する(位置);
            match id列.get_mut(書込先) {
                Some(枠) => *枠 = idへ変換する(添字),
                None => panic!("段別の書込位置が群のID列の内側に収まるという不変条件に違反した: {書込先}"),
            }
        }
    }
}

fn 数へ変換する(値: u32) -> usize {
    usize::try_from(値).unwrap_or_else(|_| panic!("段別の書込位置がusizeに収まらない: {値}"))
}

/// 群可視材料の生成時に個体数がu32へ収まることを確かめてあるため、この変換は必ず成功する。
fn idへ変換する(添字: usize) -> u32 {
    u32::try_from(添字).unwrap_or_else(|_| panic!("群可視材料の個体数がu32に収まるという不変条件に違反した"))
}
