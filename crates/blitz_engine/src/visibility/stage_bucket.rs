//! 群1つぶんの判定を、パス別・LOD段別の区間へ並べ替える工程。受け取るのは個体ごとの(段番号, 可視パス集合)の並び、
//! 書き出すのはパスの正典順(シーン→距離区分0から距離区分3)に区間を並べたID列と、段ごとのパス別区間である。
//!
//! 同じ個体IDが複数の距離区分の区間へ現れるため、列は全個体の並べ替えではなく、長さは可視の有無で毎フレーム変わる。
//! 4区分並べ(段の内側を`[シーンのみ][両方][シャドウのみ][不可視]`に置く形)の後継であり、1個体が複数の距離区分へ
//! 同時に所属しうる時点で、任意の5集合を1本の列の連続区間で表すことができなくなったことによる
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」)。
//!
//! パスごとの可視数を個体を積む走査で数えないのは、その値が段別集計のパス別件数を段でたたんだ合計に等しく、
//! 同じ述語を個体1件につき二度評価することになるためである。距離区分の和集合だけは件数の和では出せない
//! (複数の距離区分へ属する個体を重複して数えてしまう)ため、ここで真偽の数として数える。
//!
//! 作業領域を型が持ち続けるのは、群ごとに列を確保して捨てることを毎フレーム繰り返さないためである。
//! 段ごとのパス別の件数と書込位置は`tally`が持つ。

mod tally;
#[cfg(test)]
mod write_tests;

use blitz_render::段別描画範囲;

use super::count::群のパス別可視数;
use super::visible_pass_set::可視パス集合;
use tally::段別集計;

#[derive(Clone, Copy)]
struct 個体判定 {
    段番号: u8,
    パス別ビット列: u8,
}

#[derive(Default)]
pub(super) struct 段別並べ替え {
    個体別判定: Vec<個体判定>,
    距離区分の和集合: usize,
    集計: 段別集計,
}

impl 段別並べ替え {
    pub(super) fn 群を始める(&mut self, 段数: usize) {
        self.個体別判定.clear();
        self.距離区分の和集合 = 0;
        self.集計.群を始める(段数);
    }

    pub(super) fn 個体を積む(&mut self, 段番号: u8, 可視: 可視パス集合) {
        let パス別ビット列 = 可視.パス別ビット列();
        self.集計.個体を数える(usize::from(段番号), パス別ビット列);
        self.距離区分の和集合 += usize::from(可視.いずれかの距離区分に可視か());
        self.個体別判定.push(個体判定 {
            段番号, パス別ビット列
        });
    }

    /// 積んだ判定のパス別の可視数。段別集計の件数から導くため、書き出しの前後どちらで呼んでも同じ値になる。
    pub(super) fn パス別可視数(&self) -> 群のパス別可視数 {
        let (シーン, 距離区分別) = self.集計.パス別合計();
        群のパス別可視数 {
            シーン,
            距離区分別,
            距離区分の和集合: self.距離区分の和集合,
        }
    }

    pub(super) fn 書き出す(&mut self, id列: &mut Vec<u32>, 段範囲列: &mut Vec<段別描画範囲>) {
        let 基準 = id列.len();
        let 総数 = self.集計.区間を据えて範囲を積む(段範囲列);
        id列.resize(基準 + 数へ変換する(総数), 0);
        for (添字, 判定) in self.個体別判定.iter().enumerate() {
            let id = idへ変換する(添字);
            let 書込位置 = self.集計.段の書込位置(usize::from(判定.段番号));
            for (パス添字, 位置) in 書込位置.iter_mut().enumerate() {
                if (判定.パス別ビット列 >> パス添字) & 1 == 0 {
                    continue;
                }
                let 書込先 = 基準 + 数へ変換する(*位置);
                *位置 = 位置.saturating_add(1);
                match id列.get_mut(書込先) {
                    Some(枠) => *枠 = id,
                    None => panic!("パス別の書込位置が群のID列の内側に収まるという不変条件に違反した: {書込先}"),
                }
            }
        }
    }
}

fn 数へ変換する(値: u32) -> usize {
    usize::try_from(値).unwrap_or_else(|_| panic!("パス別の書込位置がusizeに収まらない: {値}"))
}

/// 群可視材料の生成時に個体数がu32へ収まることを確かめてあるため、この変換は必ず成功する。
fn idへ変換する(添字: usize) -> u32 {
    u32::try_from(添字).unwrap_or_else(|_| panic!("群可視材料の個体数がu32に収まるという不変条件に違反した"))
}
