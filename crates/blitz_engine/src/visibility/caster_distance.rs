//! キャスターの候補が持つカメラからの距離の分布。担当するのは、個体1件のカメラからの距離と影を落とす距離区分の集合を
//! 受け取り、距離の帯ごとの件数を保つことである。判定は行わず、どの距離で切ると何体が残るかを人が読むための計器である。
//!
//! 距離区分別と和集合を別々に数えるのは、読みたい量が2つあるためである。個体キャスターの費用は距離区分ごとの発行数の和に
//! 連動するため費用の残存率は距離区分別の数から求め、影を落とす個体そのものの残存率は和集合から求める。
//! 距離区分別の和は複数の距離区分へ同時に属する個体を重複して数えるため、後者を前者から導くことはできない。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」

#[cfg(test)]
mod band_tests;

use blitz_math::メートル;
use blitz_render::cascade::{距離区分マスク, 距離区分数, 距離区分番号};

/// 距離帯1つの幅。既定の最大影距離300メートルを12帯へ割る細かさであり、裁定の距離の水準はこの刻みで選ぶ。
const 帯の幅: f32 = 25.0;

/// 帯の数。最後の帯だけは上限を持たず、それより遠い個体をすべて受ける。
/// 16帯で400メートルまでを覆うのは、先読み半径2のチャンク格子で最も遠い個体がその内側に収まるためである。
const 帯の数: usize = 17;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct キャスター距離分布 {
    帯別の候補数: [u64; 帯の数],
    帯別の距離区分別の可視数: [[u64; 帯の数]; 距離区分数],
    帯別の和集合の可視数: [u64; 帯の数],
}

impl Default for キャスター距離分布 {
    fn default() -> Self {
        Self {
            帯別の候補数: [0; 帯の数],
            帯別の距離区分別の可視数: [[0; 帯の数]; 距離区分数],
            帯別の和集合の可視数: [0; 帯の数],
        }
    }
}

impl キャスター距離分布 {
    /// 帯1つの幅。報告の帯番号から距離を読み戻す側は、帯の下限をこの値と番号の積として求める。
    pub const 帯の幅メートル: f32 = 帯の幅;
    /// 帯の数。最後の帯だけは上限を持たない。
    pub const 帯数: usize = 帯の数;

    pub fn 空にする(&mut self) {
        *self = Self::default();
    }

    /// 個体1件を帯へ積む。マスクはその個体が影を落とす距離区分の集合であり、可視個体の選別が使う判定と同じものである。
    pub fn 個体を積む(&mut self, カメラからの距離: メートル, マスク: 距離区分マスク) {
        let 帯 = 帯番号(カメラからの距離);
        一件足す(&mut self.帯別の候補数, 帯);
        for 番号 in 距離区分番号::全距離区分() {
            if !マスク.立っているか(番号) {
                continue;
            }
            if let Some(帯別) = self.帯別の距離区分別の可視数.get_mut(番号.添字()) {
                一件足す(帯別, 帯);
            }
        }
        if !マスク.空か() {
            一件足す(&mut self.帯別の和集合の可視数, 帯);
        }
    }

    /// 帯ごとの候補数。影を落とすかに依らず、選別が距離を読んだ個体をすべて数えた値である。
    pub fn 帯別の候補数(&self) -> [u64; 帯の数] {
        self.帯別の候補数
    }

    /// 距離区分ごとに、その距離区分へ影を落とした個体を帯へ振り分けた数。
    pub fn 帯別の距離区分別の可視数(&self) -> [[u64; 帯の数]; 距離区分数] {
        self.帯別の距離区分別の可視数
    }

    /// 1つ以上の距離区分へ影を落とした個体を帯へ振り分けた数。
    pub fn 帯別の和集合の可視数(&self) -> [u64; 帯の数] {
        self.帯別の和集合の可視数
    }
}

fn 一件足す(帯別: &mut [u64; 帯の数], 帯: usize) {
    if let Some(枠) = 帯別.get_mut(帯) {
        *枠 += 1;
    }
}

/// 距離が入る帯の番号。商を整数へ丸めず帯の上限と順に比べるのは、縮小変換を持ち込まないためであり、
/// 帯の数が十数個であるため比較の回数が丸めより短くて済むためである(`lod_threshold`の段番号の決め方と同じ規則)。
fn 帯番号(カメラからの距離: メートル) -> usize {
    let 距離 = カメラからの距離.値();
    let mut 番号 = 0;
    let mut 上限 = 帯の幅;
    while 番号 + 1 < 帯の数 && 距離 >= 上限 {
        番号 += 1;
        上限 += 帯の幅;
    }
    番号
}
