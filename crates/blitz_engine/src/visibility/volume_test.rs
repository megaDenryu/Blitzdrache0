//! 視錐台と境界の交差判定。球と軸に平行な直方体の2つを扱う。
//! どちらも「6枚のうち1枚でも完全に外側なら外」という保守的な判定であり、平面が交わる隅では
//! 視錐台の外にある境界を内と答えることがある。偽陽性を許して偽陰性を許さない方針そのものである。

use super::plane::視錐台平面;

pub(super) fn 球は視錐台の外か(平面一覧: &[視錐台平面; 6], 中心: [f32; 3], 半径: f32) -> bool {
    平面一覧.iter().any(|平面| 平面.符号付き距離(中心) < -半径)
}

/// 直方体は、平面の法線方向へ最も進んだ頂点だけを見れば足りる。その頂点が平面の外側にあるとき、
/// 直方体の全体が外側にある。
pub(super) fn 包囲領域は視錐台の外か(平面一覧: &[視錐台平面; 6], 最小: [f32; 3], 最大: [f32; 3]) -> bool {
    平面一覧.iter().any(|平面| {
        let 法線 = 平面.法線();
        let 最遠頂点 = [0, 1, 2].map(|軸| if 法線[軸] >= 0.0 { 最大[軸] } else { 最小[軸] });
        平面.符号付き距離(最遠頂点) < 0.0
    })
}
