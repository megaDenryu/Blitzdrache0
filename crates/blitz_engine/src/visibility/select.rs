//! 2段階の可視判定そのもの。群の包囲領域で1回の粗い判定を行い、通った群だけ個体の境界球で細かい判定を行う。
//! 受け皿へは可視個体の添字を昇順で追加するだけで消去はしない。呼び出し元が複数の群の結果を1本の可視ID列へ連ねるためである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」

use blitz_math::カメラ相対位置;

use super::count::可視判定計数;
use super::frustum::視錐台;
use super::group_material::群可視材料;
use super::volume_test::{包囲領域は視錐台の外か, 球は視錐台の外か};

/// `カメラ相対アンカー`は、この群を所有するチャンクの描画アンカーからカメラ大域原点を引いた値である。
/// 材料の座標はアンカー基準のため、これを足した位置がカメラ相対空間の位置になる。
pub fn 可視個体を選ぶ(
    視錐台: &視錐台, 材料: &群可視材料, カメラ相対アンカー: カメラ相対位置, 受け皿: &mut Vec<u32>
) -> 可視判定計数 {
    let 基点 = [カメラ相対アンカー.x().値(), カメラ相対アンカー.y().値(), カメラ相対アンカー.z().値()];
    let 候補数 = 材料.個体数();
    let 領域 = 材料.群の包囲領域();
    if 包囲領域は視錐台の外か(視錐台.平面一覧(), 平行移動する(領域.最小(), 基点), 平行移動する(領域.最大(), 基点))
    {
        return 可視判定計数::群を棄却した(候補数);
    }
    let mut 可視数 = 0usize;
    for (添字, 球) in 材料.個体境界球一覧().iter().enumerate() {
        if 球は視錐台の外か(視錐台.平面一覧(), 平行移動する(球.中心成分(), 基点), 球.半径値()) {
            continue;
        }
        受け皿.push(添字をidへ変換する(添字));
        可視数 += 1;
    }
    可視判定計数::個体を判定した(候補数, 可視数)
}

fn 平行移動する(座標: [f32; 3], 基点: [f32; 3]) -> [f32; 3] {
    [0, 1, 2].map(|軸| 座標[軸] + 基点[軸])
}

/// 群可視材料の生成時に個体数がu32へ収まることを確かめてあるため、この変換は必ず成功する。
fn 添字をidへ変換する(添字: usize) -> u32 {
    match u32::try_from(添字) {
        Ok(値) => 値,
        Err(_) => panic!("群可視材料の個体数がu32に収まるという不変条件に違反した"),
    }
}
