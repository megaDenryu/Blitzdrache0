//! そのフレームに距離区分ごとの可視個体をどう決めるかの方式。コンポジションルートが起動指定から1つ選び、
//! 群ごとの判定(`band_pass_test`)がそれを受け取って準備する。
//!
//! 影の視距離が「絞る」枝だけに付くのは、絞らない枝が可視判定そのものを止めた対照であり、そこへ距離の切断を
//! 重ねると「全個体が影を落とす」という対照の意味が壊れるためである。
//! `影の視距離`は`None`が本番であり、指定が無い実行は切断を1回も評価しない。
//! `全距離区分で影を落とさない`はキャスターを0にした対照であり、影を落とすのは個体を持たない描画対象(地形)だけになる。
//! シャドウパスに残る費用が深度配列の消去と保存だけになるため、解像度に追従する費用から添付処理の切片を分離できる
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」)。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」

use super::band_light_box::距離区分別の光空間直方体;
use super::shadow_range::影の視距離;

pub enum 距離区分別の可視判定<'a> {
    距離区分ごとの直方体で絞る {
        直方体: &'a 距離区分別の光空間直方体,
        影の視距離: Option<影の視距離>, // カメラからの中心距離がこの上限を超える個体を候補にしない計測専用の切断
    },
    全距離区分で全個体を可視とする, // 可視判定を止めた実行。どの距離区分も全個体を可視として扱う
    全距離区分で影を落とさない, // キャスターを0にした対照。どの距離区分も個体を1体も可視としない
}
