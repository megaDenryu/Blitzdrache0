//! 書き出しの検査。個体が2つの段へ交互に属し、同じ個体がシーンと複数の距離区分へ重複して所属する入力を
//! 判定の工程を通さずに直接与えて、書き出したID列・段別描画範囲・パス別可視数を固定する。
//! 期待値は実装と同じ計算式で導かず手で数えた固定値であり、段ごとのパス別の書込位置が前進しなくなる回帰で落ちる。
//! 実際の可視判定を通した並びは`visibility_tests::pass_interval`が見る。ここは並べ替えだけを最小の入力で見る。

use blitz_render::cascade::{距離区分マスク, 距離区分番号};
use blitz_render::{可視ID列を読むパス数, 可視パス, 段別描画範囲};

use super::段別並べ替え;
use crate::visibility::visible_pass_set::可視パス集合;

/// 段0と段1の(開始, 描画数)をパスの正典順に並べた期待値。下の入力から手で数えた固定値である。
const 期待する区間: [((u32, u32), (u32, u32)); 可視ID列を読むパス数] =
    [((0, 2), (2, 2)), ((4, 1), (5, 2)), ((7, 1), (8, 1)), ((9, 0), (9, 2)), ((11, 1), (12, 1))];

fn 可視(シーン: bool, 距離区分: &[距離区分番号]) -> 可視パス集合 {
    let マスク = 距離区分.iter().fold(距離区分マスク::空(), |集合, 番号| 集合.距離区分を立てる(*番号));
    可視パス集合::判定から生成する(シーン, マスク)
}

/// 段0へ個体0・2・4を、段1へ個体1・3・5を交互に積む。個体0はシーンと距離区分0と距離区分3、個体1は距離区分0と距離区分1、
/// 個体2はシーンと距離区分1、個体3はシーンと距離区分0と距離区分2と距離区分3、個体5はシーンと距離区分2に可視であり、
/// 個体4はどのパスからも不可視である。段の内側で個体の並びと距離区分の順が食い違うため、並べ替えが恒等写像でも、
/// 書込位置を段でたたんでも通らない。
fn 交互に積んだ並べ替え() -> 段別並べ替え {
    use 距離区分番号::{距離区分0, 距離区分1, 距離区分2, 距離区分3};
    let mut 並べ替え = 段別並べ替え::default();
    並べ替え.群を始める(2);
    並べ替え.個体を積む(0, 可視(true, &[距離区分0, 距離区分3]));
    並べ替え.個体を積む(1, 可視(false, &[距離区分0, 距離区分1]));
    並べ替え.個体を積む(0, 可視(true, &[距離区分1]));
    並べ替え.個体を積む(1, 可視(true, &[距離区分0, 距離区分2, 距離区分3]));
    並べ替え.個体を積む(0, 可視(false, &[]));
    並べ替え.個体を積む(1, 可視(true, &[距離区分2]));
    並べ替え
}

fn 書き出す() -> (Vec<u32>, Vec<段別描画範囲>) {
    let mut 並べ替え = 交互に積んだ並べ替え();
    let (mut id列, mut 段範囲列) = (Vec::new(), Vec::new());
    並べ替え.書き出す(&mut id列, &mut 段範囲列);
    (id列, 段範囲列)
}

fn 区間(段範囲列: &[段別描画範囲], 段番号: usize, パス: 可視パス) -> (u32, u32) {
    let 範囲 = 段範囲列[段番号].パス(パス);
    (範囲.開始(), 範囲.描画数())
}

/// 列はシーン[0, 2, 3, 5]・距離区分0[0, 1, 3]・距離区分1[2, 1]・距離区分2[3, 5]・距離区分3[0, 3]を
/// 正典順に連ねた13件になる。距離区分1の区間がID昇順にならないことが、区間の内側が段順に並ぶことの根拠である。
#[test]
fn 書き出したid列がパス正典順の区間と区間内の段順に並ぶ() {
    let (id列, _) = 書き出す();
    assert_eq!(id列, vec![0, 2, 3, 5, 0, 1, 3, 2, 1, 3, 5, 0, 3]);
}

#[test]
fn 段別描画範囲の開始と描画数が手で数えた値と一致する() {
    let (_, 段範囲列) = 書き出す();
    for (パス, (段0, 段1)) in 可視パス::全パス().zip(期待する区間) {
        assert_eq!(区間(&段範囲列, 0, パス), 段0, "段0の{}", パス.名前());
        assert_eq!(区間(&段範囲列, 1, パス), 段1, "段1の{}", パス.名前());
    }
    assert_eq!((段範囲列[0].個体数(), 段範囲列[1].個体数()), (3, 3));
}

#[test]
fn パス別可視数が手で数えた値と一致する() {
    let 可視数 = 交互に積んだ並べ替え().パス別可視数();
    assert_eq!(可視数.シーン, 4);
    assert_eq!(可視数.距離区分別, [3, 2, 2, 2]);
    assert_eq!(可視数.距離区分の和集合, 5, "個体4だけがどの距離区分にも影を落とさない");
}
