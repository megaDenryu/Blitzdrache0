//! 段ごとの4区分の件数と書込位置。触れるのは段ごとの集計の列だけであり、常に段数ぶんの長さを持つ。
//! 件数と書込位置を同じ型が持つのは、書込位置が件数の累計から一度に据えられ、2つが別々に動くと
//! ある区分の書込が隣の区分へはみ出すためである。段番号がこの列の内側に収まることも同じ型が守る。

use blitz_render::{パス別描画範囲, 段別描画範囲};

use super::super::instance_class::{個体区分, 区分の数};

#[derive(Default, Clone, Copy)]
struct 段の集計 {
    区分別件数: [u32; 区分の数],
    区分別書込位置: [u32; 区分の数],
}

#[derive(Default)]
pub(super) struct 段別集計 {
    段ごと: Vec<段の集計>,
}

impl 段別集計 {
    pub(super) fn 群を始める(&mut self, 段数: usize) {
        self.段ごと.clear();
        self.段ごと.resize(段数, 段の集計::default());
    }

    pub(super) fn 段数(&self) -> usize {
        self.段ごと.len()
    }

    pub(super) fn 個体を数える(&mut self, 段番号: usize, 区分: 個体区分) {
        枠(&mut self.段ごと, 段番号).区分別件数[区分.添字()] += 1;
    }

    /// その段の描画範囲を返し、次の書き出しのための4つの書込位置を区分の順に据える。
    /// 4区分を`[シーンのみ][両方][シャドウのみ][不可視]`の順に置くため、シーンの範囲は先頭2区分、
    /// シャドウの範囲は中央2区分になり、どちらも1つの連続範囲で表せる。
    pub(super) fn 段の範囲を据える(&mut self, 段番号: usize, 開始: u32) -> 段別描画範囲 {
        let 段 = 枠(&mut self.段ごと, 段番号);
        let [シーンのみ, 両方, シャドウのみ, 不可視] = 段.区分別件数;
        let 区分開始 = [開始, 開始 + シーンのみ, 開始 + シーンのみ + 両方, 開始 + シーンのみ + 両方 + シャドウのみ];
        段.区分別書込位置 = 区分開始;
        段別描画範囲::生成する(
            開始,
            シーンのみ + 両方 + シャドウのみ + 不可視,
            パス別描画範囲::生成する(開始, シーンのみ + 両方),
            パス別描画範囲::生成する(開始 + シーンのみ, 両方 + シャドウのみ),
        )
    }

    pub(super) fn 書込位置を取り出して進める(&mut self, 段番号: usize, 区分: 個体区分) -> u32 {
        let 枠 = &mut 枠(&mut self.段ごと, 段番号).区分別書込位置[区分.添字()];
        let 位置 = *枠;
        *枠 += 1;
        位置
    }
}

/// 段番号は原型の段数の内側に収まる。破れは呼び出し側の不変条件違反である。
fn 枠(一覧: &mut [段の集計], 段番号: usize) -> &mut 段の集計 {
    match 一覧.get_mut(段番号) {
        Some(値) => 値,
        None => panic!("段別の集計が原型の段数ぶんの長さを持つという不変条件に違反した: 段番号{段番号}"),
    }
}
