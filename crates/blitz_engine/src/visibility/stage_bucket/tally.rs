//! 段ごとのパス別の件数と書込位置。触れるのは段ごとの集計の列だけであり、常に段数ぶんの長さを持つ。
//! 件数と書込位置を同じ型が持つのは、書込位置が件数の累計から一度に据えられ、2つが別々に動くと
//! あるパスの書込が隣のパスの区間へはみ出すためである。段番号がこの列の内側に収まることも同じ型が守る。
//!
//! 区間の開始を据える順序はパス(シーン→帯0から帯3)を外、段番号を内に置いた正典順である。
//! この順序が可視ID列の並びそのものであり、レンダラー側の区間の配置の検査も同じ順序を根拠にする
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の帯別区間(4区分並べの後継)」)。

use blitz_render::{パス別描画範囲, 可視ID列を読むパス数, 可視パス, 段別描画範囲};

use super::super::visible_pass_set::可視パス集合;

#[derive(Default, Clone, Copy)]
struct 段の集計 {
    個体数: u32,
    パス別件数: [u32; 可視ID列を読むパス数],
    パス別書込位置: [u32; 可視ID列を読むパス数],
}

#[derive(Default)]
pub(super) struct 段別集計 {
    段ごと: Vec<段の集計>,
}

impl 段別集計 {
    pub(super) fn 群を始める(&mut self, 段数: usize) {
        self.段ごと.clear();
        self.段ごと.resize(段数, 段の集計::default());
    }

    pub(super) fn 個体を数える(&mut self, 段番号: usize, 可視: 可視パス集合) {
        let 段 = 枠(&mut self.段ごと, 段番号);
        段.個体数 = 段.個体数.saturating_add(1);
        for パス in 可視パス::全パス() {
            if 可視.パスに可視か(パス) {
                段.パス別件数[パス.添字()] = 段.パス別件数[パス.添字()].saturating_add(1);
            }
        }
    }

    /// 正典順に区間の開始を据えながら段ごとの描画範囲を積み、全区間の件数の合計を返す。
    /// 合計がその群のID列の長さになる。
    pub(super) fn 区間を据えて範囲を積む(&mut self, 段範囲列: &mut Vec<段別描画範囲>) -> u32 {
        let mut パス区間の開始 = [0u32; 可視ID列を読むパス数];
        let mut 累計 = 0u32;
        for パス in 可視パス::全パス() {
            パス区間の開始[パス.添字()] = 累計;
            for 段 in &self.段ごと {
                累計 = 累計.saturating_add(段.パス別件数[パス.添字()]);
            }
        }
        for 段 in &mut self.段ごと {
            let mut 範囲 = [パス別描画範囲::生成する(0, 0); 可視ID列を読むパス数];
            for パス in 可視パス::全パス() {
                let 添字 = パス.添字();
                let 開始 = パス区間の開始[添字];
                段.パス別書込位置[添字] = 開始;
                範囲[添字] = パス別描画範囲::生成する(開始, 段.パス別件数[添字]);
                パス区間の開始[添字] = 開始.saturating_add(段.パス別件数[添字]);
            }
            段範囲列.push(段別描画範囲::生成する(段.個体数, 範囲));
        }
        累計
    }

    pub(super) fn 書込位置を取り出して進める(&mut self, 段番号: usize, パス: 可視パス) -> u32 {
        let 枠 = &mut 枠(&mut self.段ごと, 段番号).パス別書込位置[パス.添字()];
        let 位置 = *枠;
        *枠 = 枠.saturating_add(1);
        位置
    }
}

/// 段番号は原型の段数の内側に収まる。破れは呼び出し側の不変条件違反である。
fn 枠(一覧: &mut [段の集計], 段番号: usize) -> &mut 段の集計 {
    match 一覧.get_mut(段番号) {
        Some(値) => 値,
        None => panic!("段別の集計が原型の段数ぶんの長さを持つという不変条件に違反した: 段番号{段番号}"),
    }
}
