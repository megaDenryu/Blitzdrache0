//! 帯ごとのシャドウ判定。受け取るのは帯別の判定方式と群の包囲領域とカメラ相対アンカー、返すのは
//! 個体1件ごとにその個体が影を落とす帯のマスクである。
//!
//! 群の粗い判定を帯ごとに1回だけ済ませて群のマスクを作り、以後はそのマスクが立った帯についてだけ個体の球判定を行う。
//! 全個体へ常に帯数ぶんの球判定を行うと、OW4で制定した群選択2.0msの予算を破りうるためである
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の帯別区間(4区分並べの後継)」)。
//!
//! 触れるのは帯ごとの視錐台判定と群のマスクだけであり、群の状態も受け皿も持たない。

use blitz_render::cascade::{帯マスク, 帯数, 帯番号};

use super::frustum::視錐台;
use super::pass_test::パス判定;
use crate::軸平行包囲領域;

/// そのフレームに帯ごとの可視個体をどう決めるか。帯別に絞らない実行ではどの帯も全個体を可視として扱う。
pub enum 帯別可視判定<'a> {
    帯ごとの視錐台で絞る(&'a [視錐台; 帯数]),
    /// 可視判定を止めた実行。どの帯も全個体を可視として扱う。
    全帯で全個体を可視とする,
}

impl<'a> 帯別可視判定<'a> {
    fn 帯の視錐台(&self, 番号: 帯番号) -> Option<&'a 視錐台> {
        match self {
            Self::帯ごとの視錐台で絞る(一覧) => Some(&一覧[番号.添字()]),
            Self::全帯で全個体を可視とする => None,
        }
    }
}

pub(super) struct 帯別判定<'a> {
    帯ごと: [パス判定<'a>; 帯数],
    /// 群の包囲領域が交差した帯。立っていない帯では個体の球判定を1回も行わない。
    群のマスク: 帯マスク,
}

impl<'a> 帯別判定<'a> {
    pub(super) fn 準備する(方式: &帯別可視判定<'a>, 領域: 軸平行包囲領域, 基点: [f32; 3]) -> Self {
        let 帯ごと = 帯番号::全帯().map(|番号| パス判定::準備する(方式.帯の視錐台(番号), 領域, 基点));
        let mut 群のマスク = 帯マスク::空();
        for 番号 in 帯番号::全帯() {
            if 帯ごと[番号.添字()].群が通ったか() {
                群のマスク = 群のマスク.帯を立てる(番号);
            }
        }
        Self { 帯ごと, 群のマスク }
    }

    /// いずれかの帯が個体ごとの視錐台判定を行うか。
    pub(super) fn 個体を判定するか(&self) -> bool {
        帯番号::全帯().into_iter().any(|番号| self.帯ごと[番号.添字()].個体を判定するか())
    }

    /// この個体が影を落とす帯のマスク。群のマスクが立っていない帯は球判定を省く。
    pub(super) fn 個体のマスク(&self, 中心: [f32; 3], 半径: f32) -> 帯マスク {
        let mut マスク = 帯マスク::空();
        for 番号 in 帯番号::全帯() {
            if self.群のマスク.立っているか(番号) && self.帯ごと[番号.添字()].可視か(中心, 半径) {
                マスク = マスク.帯を立てる(番号);
            }
        }
        マスク
    }
}
