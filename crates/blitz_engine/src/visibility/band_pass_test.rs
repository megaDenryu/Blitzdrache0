//! 帯ごとのシャドウ判定。受け取るのは帯別の判定方式と群の包囲領域とカメラ相対アンカー、返すのは
//! 個体1件ごとにその個体が影を落とす帯のマスクである。
//!
//! 群の粗い判定を帯ごとに1回だけ済ませて群のマスクを作り、以後はそのマスクが立った帯についてだけ個体の判定を行う。
//! 個体の判定は、中心を光空間へ1回写してから帯ごとの区間と比べる形である。帯ごとに視錐台の平面6枚を評価すると
//! 個体1件あたり24枚になり、OW4で制定した群選択2.0msの予算を破る
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の帯別区間(4区分並べの後継)」)。
//!
//! 触れるのは帯別の直方体と群のマスクだけであり、群の状態も受け皿も持たない。

use blitz_render::cascade::{帯マスク, 帯番号};

use super::band_light_box::帯別光空間直方体;
use super::pass_test::平行移動する;
use crate::軸平行包囲領域;

/// そのフレームに帯ごとの可視個体をどう決めるか。帯別に絞らない実行ではどの帯も全個体を可視として扱う。
pub enum 帯別可視判定<'a> {
    帯ごとの直方体で絞る(&'a 帯別光空間直方体),
    /// 可視判定を止めた実行。どの帯も全個体を可視として扱う。
    全帯で全個体を可視とする,
}

pub(super) struct 帯別判定<'a> {
    /// 絞る帯別の直方体。`None`のときはどの帯も全個体を可視として扱う。
    直方体: Option<&'a 帯別光空間直方体>,
    /// 群の包囲領域が交差した帯。立っていない帯では個体の判定を1回も行わない。絞らない実行では全帯が立つ。
    群のマスク: 帯マスク,
}

impl<'a> 帯別判定<'a> {
    pub(super) fn 準備する(方式: &帯別可視判定<'a>, 領域: 軸平行包囲領域, 基点: [f32; 3]) -> Self {
        let 直方体 = match 方式 {
            帯別可視判定::帯ごとの直方体で絞る(直方体) => 直方体,
            帯別可視判定::全帯で全個体を可視とする => {
                return Self {
                    直方体: None,
                    群のマスク: 帯マスク::全帯(),
                };
            }
        };
        let 群の区間 = 直方体.包囲領域の区間(平行移動する(領域.最小(), 基点), 平行移動する(領域.最大(), 基点));
        let mut 群のマスク = 帯マスク::空();
        for 番号 in 帯番号::全帯() {
            if 直方体.帯の区間(番号).区間と重なるか(群の区間) {
                群のマスク = 群のマスク.帯を立てる(番号);
            }
        }
        Self {
            直方体: Some(直方体),
            群のマスク,
        }
    }

    /// いずれかの帯が個体ごとの判定を行うか。絞らない方式と、全帯が粗い判定で棄却された群では行わない。
    pub(super) fn 個体を判定するか(&self) -> bool {
        self.直方体.is_some() && !self.群のマスク.空か()
    }

    /// この個体が影を落とす帯のマスク。群のマスクが立っていない帯は判定を省く。
    pub(super) fn 個体のマスク(&self, 中心: [f32; 3], 半径: f32) -> 帯マスク {
        let Some(直方体) = self.直方体 else {
            return self.群のマスク;
        };
        if self.群のマスク.空か() {
            return 帯マスク::空();
        }
        let 光空間の中心 = 直方体.写す(中心);
        let mut マスク = 帯マスク::空();
        for 番号 in 帯番号::全帯() {
            if self.群のマスク.立っているか(番号) && 直方体.帯の区間(番号).球と交わるか(光空間の中心, 半径) {
                マスク = マスク.帯を立てる(番号);
            }
        }
        マスク
    }
}
