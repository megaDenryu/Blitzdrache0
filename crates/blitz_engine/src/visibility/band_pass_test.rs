//! 距離区分ごとのシャドウ判定。受け取るのは距離区分別の判定方式と群の包囲領域とカメラ相対アンカー、返すのは
//! 個体1件ごとにその個体が影を落とす距離区分のマスクである。
//!
//! 群の粗い判定を距離区分ごとに1回だけ済ませて群のマスクを作り、以後はそのマスクが立った距離区分についてだけ個体の判定を行う。
//! 個体の判定は、中心を光空間へ1回写してから距離区分ごとの区間と比べる形である。距離区分ごとに視錐台の平面6枚を評価すると
//! 個体1件あたり24枚になり、OW4で制定した可視個体の選別2.0msの予算を破る
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」)。
//!
//! 触れるのは距離区分別の直方体と群のマスクだけであり、群の状態も受け皿も持たない。

use blitz_render::cascade::{距離区分マスク, 距離区分番号};

use super::band_light_box::距離区分別の光空間直方体;
use super::pass_test::平行移動する;
use crate::軸平行包囲領域;

/// そのフレームに距離区分ごとの可視個体をどう決めるか。距離区分別に絞らない実行ではどの距離区分も全個体を可視として扱う。
pub enum 距離区分別の可視判定<'a> {
    距離区分ごとの直方体で絞る(&'a 距離区分別の光空間直方体),
    /// 可視判定を止めた実行。どの距離区分も全個体を可視として扱う。
    全距離区分で全個体を可視とする,
}

pub(super) struct 距離区分別の判定<'a> {
    /// 絞る距離区分別の直方体。`None`のときはどの距離区分も全個体を可視として扱う。
    直方体: Option<&'a 距離区分別の光空間直方体>,
    /// 群の包囲領域が交差した距離区分。立っていない距離区分では個体の判定を1回も行わない。絞らない実行では全距離区分が立つ。
    群のマスク: 距離区分マスク,
}

impl<'a> 距離区分別の判定<'a> {
    pub(super) fn 準備する(方式: &距離区分別の可視判定<'a>, 領域: 軸平行包囲領域, 基点: [f32; 3]) -> Self {
        let 直方体 = match 方式 {
            距離区分別の可視判定::距離区分ごとの直方体で絞る(直方体) => 直方体,
            距離区分別の可視判定::全距離区分で全個体を可視とする => {
                return Self {
                    直方体: None,
                    群のマスク: 距離区分マスク::全距離区分(),
                };
            }
        };
        let 群の区間 = 直方体.包囲領域の区間(平行移動する(領域.最小(), 基点), 平行移動する(領域.最大(), 基点));
        let mut 群のマスク = 距離区分マスク::空();
        for 番号 in 距離区分番号::全距離区分() {
            if 直方体.距離区分の区間(番号).区間と重なるか(群の区間) {
                群のマスク = 群のマスク.距離区分を立てる(番号);
            }
        }
        Self {
            直方体: Some(直方体),
            群のマスク,
        }
    }

    /// いずれかの距離区分が個体ごとの判定を行うか。絞らない方式と、全距離区分が粗い判定で棄却された群では行わない。
    pub(super) fn 個体を判定するか(&self) -> bool {
        self.直方体.is_some() && !self.群のマスク.空か()
    }

    /// この個体が影を落とす距離区分のマスク。群のマスクが立っていない距離区分は判定を省く。
    pub(super) fn 個体のマスク(&self, 中心: [f32; 3], 半径: f32) -> 距離区分マスク {
        let Some(直方体) = self.直方体 else {
            return self.群のマスク;
        };
        if self.群のマスク.空か() {
            return 距離区分マスク::空();
        }
        let 光空間の中心 = 直方体.写す(中心);
        let mut マスク = 距離区分マスク::空();
        for 番号 in 距離区分番号::全距離区分() {
            if self.群のマスク.立っているか(番号) && 直方体.距離区分の区間(番号).球と交わるか(光空間の中心, 半径)
            {
                マスク = マスク.距離区分を立てる(番号);
            }
        }
        マスク
    }
}
