//! 1回の可視判定が数えた件数。候補数・個体判定数・パス別の可視数・距離区分の和集合の可視数を別々に持つ。
//! 個体判定数を候補数と別に持つのは、粗い判定で群ごと棄却したときに個体の判定が1回も走らないことを、
//! 呼び出し元と検査が観測できるようにするためである。2段階の粗い判定はこの数が0になることでしか確かめられない。
//! 可視数をパスごとに持つのは、シーンと距離区分0から距離区分3が別々の視錐台で判定され、値が一致するとは限らないためである。
//! 距離区分の和集合の可視数を別に持つのは、距離区分別の可視数の和が複数の距離区分へ同時に所属する個体を重複して数えるためである。
//! 「影を落とすべき個体が1体も落ちていない」ことはこの和集合の数だけが言える。

use blitz_render::cascade::距離区分数;

/// 1つの群の判定が数えたパスごとの可視数。段別集計のパス別件数を段でたたんだ合計から導き、
/// 個体を積む走査でも書き出しの走査でも数え直さない。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub(super) struct 群のパス別可視数 {
    pub(super) シーン: usize,
    pub(super) 距離区分別: [usize; 距離区分数],
    /// 1つ以上の距離区分へ影を落とした個体の数。
    pub(super) 距離区分の和集合: usize,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 可視判定計数 {
    候補数: usize,
    個体判定数: usize,
    シーン可視数: usize,
    距離区分別の可視数: [usize; 距離区分数],
    距離区分の和集合の可視数: usize,
}

impl 可視判定計数 {
    /// `個体判定を行ったか`は、シーンと距離区分のうち少なくとも1つが個体ごとの視錐台判定を実際に走らせたかである。
    /// どれも走らせない場合(すべてが粗い判定で群ごと棄却したか、視錐台で絞らない方式)に個体判定数が0になる。
    pub(super) fn 生成する(候補数: usize, 個体判定を行ったか: bool, 可視数: 群のパス別可視数) -> Self {
        Self {
            候補数,
            個体判定数: if 個体判定を行ったか { 候補数 } else { 0 },
            シーン可視数: 可視数.シーン,
            距離区分別の可視数: 可視数.距離区分別,
            距離区分の和集合の可視数: 可視数.距離区分の和集合,
        }
    }

    /// 群ごとの計数をフレーム全体へ足し合わせる。個体判定数も足すのは、個体の判定を実際に走らせた群の候補数の合計に等しく、
    /// 2段階判定がフレーム全体でどれだけ効いたかをその値が表すためである。
    pub fn 足し合わせる(self, 他: Self) -> Self {
        Self {
            候補数: self.候補数 + 他.候補数,
            個体判定数: self.個体判定数 + 他.個体判定数,
            シーン可視数: self.シーン可視数 + 他.シーン可視数,
            距離区分別の可視数: 足し合わせた距離区分別(self.距離区分別の可視数, 他.距離区分別の可視数),
            距離区分の和集合の可視数: self.距離区分の和集合の可視数 + 他.距離区分の和集合の可視数,
        }
    }

    pub fn 候補数(&self) -> usize {
        self.候補数
    }

    pub fn 個体判定数(&self) -> usize {
        self.個体判定数
    }

    pub fn シーン可視数(&self) -> usize {
        self.シーン可視数
    }

    pub fn 距離区分別の可視数(&self) -> [usize; 距離区分数] {
        self.距離区分別の可視数
    }

    /// 1つ以上の距離区分へ影を落とした個体の数。距離区分別の可視数の和と違い、複数の距離区分へ属する同じ個体を重複して数えない。
    pub fn 距離区分の和集合の可視数(&self) -> usize {
        self.距離区分の和集合の可視数
    }
}

fn 足し合わせた距離区分別(左: [usize; 距離区分数], 右: [usize; 距離区分数]) -> [usize; 距離区分数] {
    let mut 和 = [0; 距離区分数];
    for (枠, (左の値, 右の値)) in 和.iter_mut().zip(左.into_iter().zip(右)) {
        *枠 = 左の値 + 右の値;
    }
    和
}
