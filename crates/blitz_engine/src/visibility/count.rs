//! 1回の可視判定が数えた件数。候補数・個体判定数・パス別の可視数を別々に持つ。
//! 個体判定数を候補数と別に持つのは、粗い判定で群ごと棄却したときに個体の判定が1回も走らないことを、
//! 呼び出し元と検査が観測できるようにするためである。2段階の粗い判定はこの数が0になることでしか確かめられない。
//! 可視数をパスごとに持つのは、シーンとシャドウが別々の視錐台で判定され、2つの数が一致するとは限らないためである。

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 可視判定計数 {
    候補数: usize,
    個体判定数: usize,
    シーン可視数: usize,
    シャドウ可視数: usize,
}

impl 可視判定計数 {
    /// `個体判定を行ったか`は、2つのパスのうち少なくとも一方が個体ごとの視錐台判定を実際に走らせたかである。
    /// どちらも走らせない場合(両パスが粗い判定で群ごと棄却したか、どちらも視錐台で絞らない方式)に個体判定数が0になる。
    pub(super) fn 生成する(候補数: usize, 個体判定を行ったか: bool, シーン可視数: usize, シャドウ可視数: usize) -> Self {
        Self {
            候補数,
            個体判定数: if 個体判定を行ったか { 候補数 } else { 0 },
            シーン可視数,
            シャドウ可視数,
        }
    }

    pub fn 候補数(&self) -> usize {
        self.候補数
    }

    pub fn 個体判定数(&self) -> usize {
        self.個体判定数
    }

    pub fn シーン可視数(&self) -> usize {
        self.シーン可視数
    }

    pub fn シャドウ可視数(&self) -> usize {
        self.シャドウ可視数
    }
}
