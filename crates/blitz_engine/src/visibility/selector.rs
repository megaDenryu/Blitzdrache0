//! 群ごとの可視判定と段選択を回す操作サービス。そのフレームの選択が書き込む段別ID受け皿と、
//! 計測指定のある実行だけが数えるキャスターの距離分布を所有し、群を1つずつ受けて自分の中へ積む。
//!
//! 書き込み先を呼び出し側に持たせないのは、走査ごとに差し替えられる形にすると、ある群の選択の区間が
//! 別のフレームの列を指す呼び出しを署名の上で書けてしまうためである。毎フレームVecを確保して直後に捨てないことも、
//! この型が列を所有し続けることで自然に守られる(容量はフレームをまたいで残る)。
//!
//! 個体別の段の記憶だけを引数で受けるのは、記憶が群ごとに1つあり、その寿命を群の登録を持つ側が握るためである。
//! この型が持てるのは群をまたいで1本しかない受け皿と分布の2つだけである。
//!
//! 走査そのものは`combined_select`と`caster_distance_scan`がこの型のメソッドとして持つ。

use blitz_render::段別描画範囲;

use super::caster_distance::キャスター距離分布;
use super::stage_tray::段別ID受け皿;

#[derive(Default)]
pub struct 可視個体と段の選別係 {
    pub(super) 段別: 段別ID受け皿,
    pub(super) 距離分布: キャスター距離分布,
}

impl 可視個体と段の選別係 {
    pub fn 生成する() -> Self {
        Self::default()
    }

    /// 次のフレームの走査へ備えて、積んだ列と分布を空にする。確保した容量は残る。
    pub fn 空にする(&mut self) {
        self.段別.空にする();
        self.距離分布.空にする();
    }

    /// そのフレームに積んだ全群のID列。
    pub fn id列(&self) -> &[u32] {
        self.段別.id列()
    }

    /// そのフレームに積んだ全群の段のパス別区間。
    pub fn 段範囲列(&self) -> &[段別描画範囲] {
        self.段別.段範囲列()
    }

    pub fn id列の長さ(&self) -> usize {
        self.段別.id列の長さ()
    }

    pub fn 段範囲列の長さ(&self) -> usize {
        self.段別.段範囲列の長さ()
    }

    /// そのフレームに数えたキャスター候補の距離分布。計測指定が無い実行では全帯が0のままである。
    pub fn キャスターの距離分布(&self) -> キャスター距離分布 {
        self.距離分布
    }
}
