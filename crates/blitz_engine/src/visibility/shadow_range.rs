//! 影の候補にする個体のカメラからの中心距離の上限。担当するのは、上限の値と「この距離は上限の外か」の答えである。
//!
//! **これは計測専用の単純切断である。** 中心距離だけで切ると、低い太陽で上限の外側にある個体が上限の内側の地形へ
//! 落とす長い影も消える(現在のキャスター余白が守っているのはまさにその影である)。裁定材料を作るために
//! 「同じ残存個体率を作ったときの費用と絵」を測るための切断であり、保護契約を持つ本実装ではない。
//! 本実装は中心距離でなく、光の方向へ伸ばしたキャスターの境界と保護したい受光領域の交差で残す形になる。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」

use blitz_math::メートル;

use super::error::可視判定エラー;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 影の視距離 {
    上限: メートル,
}

impl 影の視距離 {
    /// 0以下と非有限を拒むのは、どちらも「影を落とす個体が1体も無い」か「比較が常に偽になる」かのどちらかになり、
    /// 距離の水準として意味を持たないためである。
    pub fn 生成する(上限: メートル) -> Result<Self, 可視判定エラー> {
        if !上限.値().is_finite() || 上限.値() <= 0.0 {
            return Err(可視判定エラー::影の視距離不正);
        }
        Ok(Self { 上限 })
    }

    /// この距離の個体を影の候補から外すか。境界球の半径を足さない保守的でない比較であることが、
    /// この切断を計測専用に留める理由の1つである(半径ぶん外側の影は上限の内側にも落ちうる)。
    pub(super) fn 外か(self, カメラからの距離: メートル) -> bool {
        カメラからの距離.値() > self.上限.値()
    }
}
