//! 描画束の組み立ての検査が使う材料。二材質の集合、スロット番号の並びから作る形状、その2つを組み立て工程へ通す呼び出しを持つ。
//! 材料を検査本体と分けて持つのは、正の検査と負の検査が同じ材料を読むためである。

use crate::asset::{
    マテリアルデータ, メッシュデータ, メッシュプリミティブ, メッシュ頂点属性, 描画形状, 材質スロットID, 材質スロット割当, 材質集合, 金属粗さPBRデータ,
};

use super::error::描画束エラー;
use super::list::描画束一覧;
use super::描画束を組み立てる;

/// スロット0とスロット1に別々の材質を割り当てた集合。金属度係数だけを見ればどちらが選ばれたか分かる。
pub(super) fn 二材質の集合() -> 材質集合 {
    let 割当 = |番号: u32, 金属度係数: f32| 材質スロット割当 {
        スロット: 材質スロットID::生成する(番号),
        マテリアル: マテリアルデータ::金属粗さPBR(金属粗さPBRデータ {
            ベースカラー: None,
            金属粗さ: None,
            法線マップ: None,
            ベースカラー係数: [1.0, 1.0, 1.0, 1.0],
            金属度係数,
            粗さ係数: 1.0,
        }),
    };
    match 材質集合::生成する(vec![割当(0, 0.25), 割当(1, 0.75)]) {
        Ok(値) => 値,
        Err(誤り) => panic!("検査用の二材質の集合を作れなかった: {誤り}"),
    }
}

/// 与えたスロット番号の並びと同じ順序のプリミティブ列を持つ1段のメッシュ。空の並びはプリミティブを持たないメッシュになる。
pub(super) fn 形状を作る(スロット番号一覧: &[u32]) -> 描画形状 {
    let プリミティブ列 = スロット番号一覧
        .iter()
        .map(|番号| メッシュプリミティブ {
            インデックス開始: 0,
            インデックス数: 1,
            頂点基準: 0,
            材質スロット: 材質スロットID::生成する(*番号),
        })
        .collect();
    描画形状::通常メッシュ(メッシュデータ {
        頂点一覧: vec![メッシュ頂点属性 {
            位置: [0.0, 0.0, 0.0],
            法線: [0.0, 1.0, 0.0],
            接線: [1.0, 0.0, 0.0, 1.0],
            uv: [0.0, 0.0],
        }],
        インデックス一覧: vec![0],
        スキン頂点属性一覧: None,
        プリミティブ列,
    })
}

pub(super) fn 組み立てる(スロット番号一覧: &[u32], 描画対象添字: usize) -> Result<描画束一覧, 描画束エラー> {
    let mut 受け皿 = 描画束一覧::生成する();
    描画束を組み立てる(&形状を作る(スロット番号一覧), &二材質の集合(), 描画対象添字, &mut 受け皿)?;
    Ok(受け皿)
}
