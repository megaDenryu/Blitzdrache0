//! 描画束: 静的な描画片へ、その片を塗る材質と、その片が読む可視個体区間の参照を結んだ描画発行の単位。
//! 材質を材質集合の中の割当添字で持つのは、資源表世代をまたいで有効な大域の材質IDがまだ無いためである。
//! 添字は描画対象が持つ材質集合の中でだけ意味を持ち、その集合と一緒に読む。マルチマテリアルの段Cで材質IDへ置き換える。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「可視ID列の契約」

use super::fragment::静的描画片;
use super::visible_interval::可視個体区間参照;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 描画束 {
    描画片: 静的描画片,
    材質割当添字: usize,
    可視個体区間: 可視個体区間参照,
}

impl 描画束 {
    /// `材質割当添字`は描画片の材質スロットIDを描画対象の材質集合で解決した結果であり、解決に失敗した組み合わせでこの型を作ってはならない。
    /// 解決を組み立て時に済ませるのは、描画発行のたびにスロットから材質を探し直さないためである。
    pub fn 生成する(描画片: 静的描画片, 材質割当添字: usize, 可視個体区間: 可視個体区間参照) -> Self {
        Self {
            描画片,
            材質割当添字,
            可視個体区間,
        }
    }

    pub fn 描画片(self) -> 静的描画片 {
        self.描画片
    }

    pub fn 材質割当添字(self) -> usize {
        self.材質割当添字
    }

    pub fn 可視個体区間(self) -> 可視個体区間参照 {
        self.可視個体区間
    }
}
