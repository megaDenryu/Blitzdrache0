//! プリミティブ描画範囲: 1つのプリミティブが描くインデックスの区間と頂点基準。組み立てのときにメッシュのプリミティブ列から値を写す。
//! 添字でなく値を持つのは、描画発行の時点で元のメッシュデータが既に無いためである。起動時のシーンデータはレンダラーへ渡した後に分解され、
//! チャンクのシーンもGPU転送の完了とともに破棄される。プリミティブ添字だけを持つと、その添字が指す先がどこにも残らない。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「可視ID列の契約」

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct プリミティブ描画範囲 {
    インデックス開始: usize,
    インデックス数: usize,
    頂点基準: u32,
}

impl プリミティブ描画範囲 {
    /// 開始と数がusizeでありながら頂点基準がu32なのは、前2つがインデックス一覧の添字と長さであるのに対し、頂点基準がインデックスの値へ加える頂点番号だからである。
    /// 区間がメッシュに収まることは実行時形式の読み書きが検査済みであり、この型は検査を繰り返さない。
    pub fn 生成する(インデックス開始: usize, インデックス数: usize, 頂点基準: u32) -> Self {
        Self {
            インデックス開始,
            インデックス数,
            頂点基準,
        }
    }

    pub fn インデックス開始(self) -> usize {
        self.インデックス開始
    }

    pub fn インデックス数(self) -> usize {
        self.インデックス数
    }

    pub fn 頂点基準(self) -> u32 {
        self.頂点基準
    }
}
