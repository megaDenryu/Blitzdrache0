//! 描画束の組み立ての検査。プリミティブごとに束が1件できること、同じ描画対象の束が可視個体区間を共有すること、
//! 材質集合に無いスロットとプリミティブ不在を拒むことを見る。

use crate::asset::材質スロットID;

use super::build_fixture::{二材質の集合, 組み立てる};
use super::error::描画束エラー;

#[test]
fn 二材質のプリミティブごとに束を作り可視個体区間を共有する() {
    let Ok(一覧) = 組み立てる(&[0, 1], 3) else {
        panic!("二材質の形状で描画束を組み立てられなかった");
    };
    let [前, 後] = 一覧.一覧() else {
        panic!("2プリミティブの形状で描画束が2件にならなかった: {}件", 一覧.件数());
    };
    assert_eq!(前.描画片().プリミティブ添字(), 0);
    assert_eq!(後.描画片().プリミティブ添字(), 1);
    assert_eq!(前.描画片().材質スロット().番号を返す(), 0);
    assert_eq!(後.描画片().材質スロット().番号を返す(), 1);
    assert_ne!(前.材質割当添字(), 後.材質割当添字());
    assert_eq!(前.可視個体区間(), 後.可視個体区間());
    assert_eq!(前.可視個体区間().描画対象添字(), 3);
}

/// 未使用の最小スロットがあっても、束が指すのは参照されたスロットだけである。最小スロットを無条件に選ぶ実装ではこの検査が落ちる。
#[test]
fn 参照されないスロットの束を作らない() {
    let Ok(一覧) = 組み立てる(&[1], 0) else {
        panic!("単一材質の形状で描画束を組み立てられなかった");
    };
    let [唯一] = 一覧.一覧() else {
        panic!("1プリミティブの形状で描画束が1件にならなかった: {}件", 一覧.件数());
    };
    let 集合 = 二材質の集合();
    assert_eq!(唯一.描画片().材質スロット().番号を返す(), 1);
    assert_eq!(
        集合.添字で材質を参照する(唯一.材質割当添字()),
        集合.材質を参照する(材質スロットID::生成する(1))
    );
}

#[test]
fn 材質集合に無いスロットの参照を拒む() {
    let Err(描画束エラー::材質スロット未定義 { 番号 }) = 組み立てる(&[3], 0) else {
        panic!("材質集合に無いスロットの参照が拒まれなかった");
    };
    assert_eq!(番号, 3);
}

#[test]
fn プリミティブを持たないメッシュを拒む() {
    let Err(描画束エラー::プリミティブ列が空 { 詳細段番号 }) = 組み立てる(&[], 0) else {
        panic!("プリミティブを持たないメッシュが拒まれなかった");
    };
    assert_eq!(詳細段番号, 0);
}
