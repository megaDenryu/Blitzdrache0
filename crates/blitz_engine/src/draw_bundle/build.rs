//! 描画対象1つぶんの描画束を組み立てる工程。受け取るのは形状と材質集合と束の中での描画対象添字、積むのは詳細段ごと・プリミティブごとの描画束である。
//! 全詳細段の全プリミティブを1件ずつ展開するのは、段ごとにプリミティブ数が違ってよい契約のためである。1段だけを見て他の段の材質を決めることはできない。
//! 可視個体区間の参照は描画対象添字だけから作り、その描画対象の全描画束へ同じ値を配る。可視選別を個体・原型・詳細段について1回だけ行う契約がこれである。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「可視ID列の契約」

use crate::asset::{描画形状, 材質集合};

use super::bundle::描画束;
use super::error::描画束エラー;
use super::fragment::静的描画片;
use super::list::描画束一覧;
use super::visible_interval::可視個体区間参照;

/// 積んだ描画束は`受け皿`の末尾へ連なる。失敗したときは途中まで積んだぶんが残るため、呼び出し元は失敗を伝播して束ごと捨てる。
pub fn 描画束を組み立てる(
    形状: &描画形状,
    材質集合: &材質集合,
    描画対象添字: usize,
    受け皿: &mut 描画束一覧,
) -> Result<(), 描画束エラー> {
    let 可視個体区間 = 可視個体区間参照::生成する(描画対象添字);
    for (詳細段番号, メッシュ) in 形状.全メッシュ().iter().enumerate() {
        if メッシュ.プリミティブ列.is_empty() {
            return Err(描画束エラー::プリミティブ列が空 { 詳細段番号 });
        }
        for (プリミティブ添字, プリミティブ) in メッシュ.プリミティブ列.iter().enumerate() {
            let Some(材質割当添字) = 材質集合.割当添字を求める(プリミティブ.材質スロット) else {
                return Err(描画束エラー::材質スロット未定義 {
                    番号: プリミティブ.材質スロット.番号を返す(),
                });
            };
            let 描画片 = 静的描画片::生成する(描画対象添字, 詳細段番号, プリミティブ添字, プリミティブ.材質スロット);
            受け皿.積む(描画束::生成する(描画片, 材質割当添字, 可視個体区間));
        }
    }
    Ok(())
}
