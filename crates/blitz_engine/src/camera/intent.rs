//! 入力層が写像するデバイス非依存のカメラ操作意図。
//! 参照: `_doc/計画/ユビキタス言語.md`「入力インテント」。

use blitz_math::ラジアン;

/// 1フレームぶんのカメラ操作意図。マウス・キーボードいずれの由来かをカメラは知らない。
///
/// 注意: `距離倍率` の「何もしない」値は0.0ではなく1.0（乗算の単位元）。
/// `Default`は導出しない（自動導出は距離倍率0.0を作り、距離を毎フレーム0にする）。
#[derive(Debug, Clone, Copy)]
pub struct カメラインテント {
    pub ヨー差分: ラジアン,
    pub ピッチ差分: ラジアン,
    pub 距離倍率: f32, // 現在の距離に掛ける倍率。1.0で変化なし
}

impl カメラインテント {
    /// 変化の無い（何も操作しなかった）インテント。
    pub fn 無操作() -> Self {
        Self {
            ヨー差分: ラジアン::生成する(0.0),
            ピッチ差分: ラジアン::生成する(0.0),
            距離倍率: 1.0,
        }
    }
}
