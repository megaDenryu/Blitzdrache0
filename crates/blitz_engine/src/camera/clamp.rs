//! オービットカメラの姿勢クランプ: ピッチ±80度、距離0.5メートル以上1000メートル以下。

use blitz_math::{メートル, ラジアン};

const ピッチ上限度: f32 = 80.0;
const 最小距離メートル: f32 = 0.5;
/// 一辺1024メートルのエディター世界を、注視点の真上から一望できる距離。縦視野角60度で縦に見渡せる幅は距離の1.155倍(2倍のtan30度)であり、
/// 1000メートルでは1155メートルとなって世界の一辺を上回る。遠クリップ距離1万メートルの内側であるため、上限まで引いても地形が切り取られない。
/// 世界ごとの初期姿勢で最も遠いものは距離150メートル(`app/scene_camera/terrain_origin_view.rs`)であり、この上限は既存の構図を1つも動かさない。
const 最大距離メートル: f32 = 1000.0;

pub(super) fn ピッチをクランプする(候補: ラジアン) -> ラジアン {
    let 上限 = ラジアン::度から(ピッチ上限度);
    let 下限 = ラジアン::度から(-ピッチ上限度);
    if 候補 > 上限 {
        上限
    } else if 候補 < 下限 {
        下限
    } else {
        候補
    }
}

/// 注視点から視点までの距離の下限。表示距離を据える検査もこの値を下限に使う。
pub(super) fn 最小距離() -> メートル {
    メートル::生成する(最小距離メートル)
}

/// 上限を置くのは、引きの操作に終わりが無いと視点が世界の外へ出て、地形も注視点も画面から消えるためである。
pub(super) fn 距離を上下限へ収める(候補: メートル) -> メートル {
    let 下限 = 最小距離();
    let 上限 = メートル::生成する(最大距離メートル);
    if 候補 < 下限 {
        下限
    } else if 候補 > 上限 {
        上限
    } else {
        候補
    }
}

#[cfg(test)]
mod tests {
    use super::{最大距離メートル, 最小距離メートル, 距離を上下限へ収める};
    use blitz_math::メートル;

    #[test]
    fn 上限を超える距離は上限で止まる() {
        assert_eq!(距離を上下限へ収める(メートル::生成する(100_000.0)), メートル::生成する(最大距離メートル));
    }

    #[test]
    fn 下限を下回る距離は下限で止まる() {
        assert_eq!(距離を上下限へ収める(メートル::生成する(0.0)), メートル::生成する(最小距離メートル));
    }

    #[test]
    fn 上下限の内側の距離はそのまま通る() {
        assert_eq!(距離を上下限へ収める(メートル::生成する(9.6)), メートル::生成する(9.6));
    }
}
