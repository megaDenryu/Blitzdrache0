//! オービットカメラの姿勢クランプ: ピッチ±80度、距離0.5m以上。

use blitz_math::{メートル, ラジアン};

const ピッチ上限度: f32 = 80.0;
const 最小距離メートル: f32 = 0.5;

pub(super) fn ピッチをクランプする(候補: ラジアン) -> ラジアン {
    let 上限 = ラジアン::度から(ピッチ上限度);
    let 下限 = ラジアン::度から(-ピッチ上限度);
    if 候補 > 上限 {
        上限
    } else if 候補 < 下限 {
        下限
    } else {
        候補
    }
}

pub(super) fn 距離を下限にする(候補: メートル) -> メートル {
    let 下限 = メートル::生成する(最小距離メートル);
    if 候補 < 下限 { 下限 } else { 候補 }
}
