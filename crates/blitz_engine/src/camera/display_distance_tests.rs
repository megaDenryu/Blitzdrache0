//! 表示距離の検査。据えられる範囲と、視点位置が表示距離から求まることと、カメラ操作の更新が表示距離を理想距離へ合わせることを見る。

use blitz_math::{メートル, ラジアン};

use super::{カメラ, カメラインテント, 表示距離エラー};

fn 距離を縮める操作() -> カメラインテント {
    カメラインテント {
        ヨー差分: ラジアン::生成する(0.0),
        ピッチ差分: ラジアン::生成する(0.0),
        距離倍率: 0.5,
    }
}

#[test]
fn 生成直後の表示距離は理想距離に等しい() {
    let カメラ = カメラ::生成する();
    assert_eq!(カメラ.表示距離(), カメラ.理想距離());
    assert_eq!(カメラ.視点ワールド位置(), カメラ.理想の視点ワールド位置());
}

/// 反証: 表示距離が視点位置へ効かなければ、遮蔽の回避が値を据えても視点が壁の中に残る。
#[test]
fn 表示距離を縮めると視点だけが注視点へ寄る() {
    let mut カメラ = カメラ::生成する();
    assert_eq!(カメラ.表示距離を据える(メートル::生成する(1.0)), Ok(()));
    assert_eq!(カメラ.表示距離(), メートル::生成する(1.0));
    assert_eq!(カメラ.理想距離(), メートル::生成する(3.0));
    assert_eq!(カメラ.視点ワールド位置().z(), メートル::生成する(1.0));
    assert_eq!(カメラ.理想の視点ワールド位置().z(), メートル::生成する(3.0));
}

#[test]
fn 理想距離より長い表示距離を拒む() {
    let mut カメラ = カメラ::生成する();
    assert_eq!(
        カメラ.表示距離を据える(メートル::生成する(3.5)),
        Err(表示距離エラー::理想距離より長い {
            表示距離: メートル::生成する(3.5),
            理想距離: メートル::生成する(3.0),
        })
    );
    assert_eq!(カメラ.表示距離(), メートル::生成する(3.0));
}

#[test]
fn 最小距離より短い表示距離を拒む() {
    let mut カメラ = カメラ::生成する();
    assert_eq!(
        カメラ.表示距離を据える(メートル::生成する(0.1)),
        Err(表示距離エラー::最小距離より短い {
            表示距離: メートル::生成する(0.1),
            最小距離: メートル::生成する(0.5),
        })
    );
}

/// 反証: 更新が表示距離を理想距離へ合わせなければ、前の描画の遮蔽が消えた後も視点が寄ったままになる。
#[test]
fn カメラ操作の更新は表示距離を新しい理想距離へ合わせる() {
    let mut カメラ = カメラ::生成する();
    assert_eq!(カメラ.表示距離を据える(メートル::生成する(1.0)), Ok(()));
    カメラ.更新する(距離を縮める操作());
    assert_eq!(カメラ.理想距離(), メートル::生成する(1.5));
    assert_eq!(カメラ.表示距離(), メートル::生成する(1.5));
}
