//! オービットカメラの表示距離。触れるのは`表示距離`と、その上限になる`距離`(理想距離)だけである。
//! 遮蔽をどれだけ避けるか・どの速さで戻るかという方針はゲーム側の「カメラの遮蔽と復帰」が持ち、ここが持つのは
//! 据えられた値の検査と、理想距離のままの視点位置を答えることだけである。
//! 参照: `_doc/設計/キャラクターの移動とカメラ.md`「判断11」

use blitz_math::{メートル, ワールド, 位置};

use super::{clamp, position, カメラ};

/// 表示距離として据えられない値を拒む理由。黙ってクランプせず、どちらの限界をどれだけ外れたかを持つ。
#[derive(Debug, Clone, Copy, PartialEq, thiserror::Error)]
pub enum 表示距離エラー {
    /// 表示距離は理想距離を越えない。遮蔽の回避は理想距離より手前へ寄せるだけである。
    #[error("表示距離{}メートルが理想距離{}メートルより長い", .表示距離.値(), .理想距離.値())]
    理想距離より長い {
        表示距離: メートル, 理想距離: メートル
    },
    /// 表示距離はオービットカメラの最小距離を割らない。近クリップ面が注視点を越えないためである。
    #[error("表示距離{}メートルが最小距離{}メートルより短い", .表示距離.値(), .最小距離.値())]
    最小距離より短い {
        表示距離: メートル, 最小距離: メートル
    },
}

impl カメラ {
    /// カメラ操作が決めた、注視点から視点までの距離。遮蔽の回避が表示距離を寄せる上限である。
    pub fn 理想距離(&self) -> メートル {
        self.距離
    }

    /// 視点のワールド位置を実際に求める距離。遮蔽が無ければ理想距離に等しい。
    pub fn 表示距離(&self) -> メートル {
        self.表示距離
    }

    /// 遮蔽の回避が決めた表示距離を据える。理想距離より長い値と最小距離より短い値は型付きエラーで拒む。
    /// 次の`更新する`が表示距離を理想距離へ合わせるため、据えた値が効くのはその描画だけである。
    pub fn 表示距離を据える(&mut self, 表示距離: メートル) -> Result<(), 表示距離エラー> {
        if 表示距離 > self.距離 {
            return Err(表示距離エラー::理想距離より長い {
                表示距離,
                理想距離: self.距離,
            });
        }
        let 最小距離 = clamp::最小距離();
        if 表示距離 < 最小距離 {
            return Err(表示距離エラー::最小距離より短い { 表示距離, 最小距離 });
        }
        self.表示距離 = 表示距離;
        Ok(())
    }

    /// 遮蔽を考えずに理想距離だけ離れた視点のワールド位置。遮蔽の回避が、注視点からここへ向けて掃引する終点に使う。
    pub fn 理想の視点ワールド位置(&self) -> 位置<ワールド> {
        position::視点位置を計算する(self.注視点, self.ヨー, self.ピッチ, self.距離)
    }

    /// カメラが見つめている点。遮蔽の回避が掃引の始点に使う。
    pub fn 注視点(&self) -> 位置<ワールド> {
        self.注視点
    }
}
