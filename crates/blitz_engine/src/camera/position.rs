//! オービットカメラの視点位置計算(球面座標)。ヨー0・ピッチ0で注視点から見て
//! +Z方向・距離ぶん離れた位置になる（既定カメラが+Z軸上に来る構図）。

use blitz_math::{メートル, ラジアン, ワールド, 位置};

pub(super) fn 視点位置を計算する(
    注視点: 位置<ワールド>,
    ヨー: ラジアン,
    ピッチ: ラジアン,
    距離: メートル,
) -> 位置<ワールド> {
    // 注意: 球面座標からの直交座標変換にはsin/cosの生f32値が要る。単位型に
    // 三角関数演算を持たせていないため、ここでのみ値を取り出す。
    let 距離値 = 距離.値();
    let ヨー値 = ヨー.値();
    let ピッチ値 = ピッチ.値();

    let x = 距離値 * ピッチ値.cos() * ヨー値.sin();
    let y = 距離値 * ピッチ値.sin();
    let z = 距離値 * ピッチ値.cos() * ヨー値.cos();

    位置::生成する(
        注視点.x() + メートル::生成する(x),
        注視点.y() + メートル::生成する(y),
        注視点.z() + メートル::生成する(z),
    )
}
