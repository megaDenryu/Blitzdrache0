//! オービットカメラ。注視点を中心にヨー・ピッチ・距離で視点を制御する。
//! 参照: `_doc/計画/ユビキタス言語.md`「オービットカメラ」。

mod clamp;
mod intent;
mod position;

use blitz_math::{クリップ, ビュー, メートル, ラジアン, ワールド, 変換};

pub use intent::カメラインテント;

const 縦視野角度: f32 = 60.0;
const 近クリップ距離: f32 = 0.1;
// Fox(体長約120単位、カメラ距離約180)が旧値100で全クリップされたため拡張した(判断48)。
// near 0.1との比2万は24bit深度で当面問題ないが、大規模シーン導入時は逆Z化を検討する。
const 遠クリップ距離: f32 = 2000.0;

/// 注視点中心に回り込む視点。ヨー・ピッチはラジアン、距離はメートルで持つ。
pub struct カメラ {
    ヨー: ラジアン,
    ピッチ: ラジアン,
    距離: メートル,
    注視点: blitz_math::位置<ワールド>,
}

impl カメラ {
    /// 既定姿勢: +Z軸上・距離3mから原点を注視する
    /// （深度の機械検証の構図。参照: 開発スレッド「判断16」）。
    pub fn 生成する() -> Self {
        Self {
            ヨー: ラジアン::生成する(0.0),
            ピッチ: ラジアン::生成する(0.0),
            距離: メートル::生成する(3.0),
            注視点: blitz_math::位置::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0)),
        }
    }

    /// インテントぶんヨー・ピッチ・距離を更新する。ピッチは±80度、距離は0.5m以上に
    /// クランプする（判断15）。
    pub fn 更新する(&mut self, インテント: カメラインテント) {
        self.ヨー = self.ヨー + インテント.ヨー差分;
        self.ピッチ = clamp::ピッチをクランプする(self.ピッチ + インテント.ピッチ差分);
        self.距離 = clamp::距離を下限にする(self.距離 * インテント.距離倍率);
    }

    /// カメラ相対フレームのビュー射影変換を組み立てる。視点を原点へ置き、ビューは回転だけを持つ。
    /// 注意: 描画対象側もカメラ大域原点を引いた位置を渡すため、ここへ視点の平行移動を入れると二重減算になる。
    /// 参照: `_doc/設計/地形とカメラ相対描画.md`「カメラ相対描画の契約」
    pub fn カメラ相対ビュー射影変換を作る(&self, アスペクト比: f32) -> 変換<ワールド, クリップ> {
        let 視点位置 = self.視点ワールド位置();
        let 原点 = blitz_math::位置::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0));
        let 相対注視点 = blitz_math::位置::生成する(
            self.注視点.x() - 視点位置.x(),
            self.注視点.y() - 視点位置.y(),
            self.注視点.z() - 視点位置.z(),
        );
        let ビュー変換: 変換<ワールド, ビュー> = 変換::注視(原点, 相対注視点);
        let 投影変換: 変換<ビュー, クリップ> = 変換::透視投影(
            ラジアン::度から(縦視野角度),
            アスペクト比,
            メートル::生成する(近クリップ距離),
            メートル::生成する(遠クリップ距離),
        );
        ビュー変換.合成する(投影変換)
    }

    /// 現在の姿勢からカメラ(視点)のワールド位置を求める。
    /// PBRのライティング計算(視線ベクトル)に使う（判断24）。
    pub fn 視点ワールド位置(&self) -> blitz_math::位置<ワールド> {
        position::視点位置を計算する(self.注視点, self.ヨー, self.ピッチ, self.距離)
    }
}
