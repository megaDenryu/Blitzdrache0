//! オービットカメラ。注視点を中心にヨー・ピッチ・距離で視点を制御する。
//! 参照: `_doc/計画/ユビキタス言語.md`「オービットカメラ」。
//! 透視投影の組み立てと、その投影の定数は`projection`にある。

mod clamp;
mod intent;
mod position;
mod projection;

use blitz_math::{メートル, ラジアン, ワールド};

pub use intent::カメラインテント;

/// 注視点中心に回り込む視点。ヨー・ピッチはラジアン、距離はメートルで持つ。
pub struct カメラ {
    ヨー: ラジアン,
    ピッチ: ラジアン,
    距離: メートル,
    注視点: blitz_math::位置<ワールド>,
}

impl カメラ {
    /// 既定姿勢: +Z軸上・距離3mから原点を注視する
    /// （深度の機械検証の構図。参照: 開発スレッド「判断16」）。
    pub fn 生成する() -> Self {
        Self {
            ヨー: ラジアン::生成する(0.0),
            ピッチ: ラジアン::生成する(0.0),
            距離: メートル::生成する(3.0),
            注視点: blitz_math::位置::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0)),
        }
    }

    /// インテントぶんヨー・ピッチ・距離を更新する。ピッチは±80度、距離は0.5m以上に
    /// クランプする（判断15）。
    pub fn 更新する(&mut self, インテント: カメラインテント) {
        self.ヨー = self.ヨー + インテント.ヨー差分;
        self.ピッチ = clamp::ピッチをクランプする(self.ピッチ + インテント.ピッチ差分);
        self.距離 = clamp::距離を下限にする(self.距離 * インテント.距離倍率);
    }

    /// 注視点をその位置へ据える。ヨー・ピッチ・距離は変わらないため、視点は据えた注視点の周りの同じ姿勢へ移る。
    /// ゲームが毎フレーム供給する位置をカメラが追う「追従」はこの1つの操作で表す。累積でなく絶対で受けるのは、
    /// 供給が1フレーム落ちても注視点が置き去りにならないためである。
    pub fn 注視点を据える(&mut self, 注視点: blitz_math::位置<ワールド>) {
        self.注視点 = 注視点;
    }

    /// 注視点を平行移動する。視点も同じだけ動くため、ヨー・ピッチ・距離を保ったままカメラだけを既知量ずらせる。
    /// 原点移動不変性の検査が、微小な移動で描画が実際に変わることを負の対照として測るために使う。
    pub fn 注視点をずらす(&mut self, x: メートル, y: メートル, z: メートル) {
        self.注視点 = blitz_math::位置::生成する(self.注視点.x() + x, self.注視点.y() + y, self.注視点.z() + z);
    }

    /// カメラが向いている方位。0が北(Zの負の向き)であり、増えると西へ回る。ゲームの移動をカメラ基準にする配線が読む。
    pub fn ヨー(&self) -> ラジアン {
        self.ヨー
    }

    /// 現在の姿勢からカメラ(視点)のワールド位置を求める。
    /// PBRのライティング計算(視線ベクトル)に使う（判断24）。
    pub fn 視点ワールド位置(&self) -> blitz_math::位置<ワールド> {
        position::視点位置を計算する(self.注視点, self.ヨー, self.ピッチ, self.距離)
    }
}
