//! 静的物理形状を持つチャンク世界の実体。板1枚の世界と同じ構成へ、建物1棟ぶんの衝突対象を添えたシーンを書く。
//!
//! 板の世界と分けるのは、既存の試験が読込量と見積の関係を数値で固定しており、そこへ節を足すと
//! 形状と関係のない試験が一斉に動くためである。形状を見る試験だけがこの世界を使う。

use std::path::PathBuf;

use super::pixels::既定画素;
use super::{生成物とカタログを作る, 目録を作る};
use crate::asset::runtime_scene_tests::静的シーンを作る;
use crate::static_shape::shape_fixture::建物1棟の形状を作る;
use crate::{カタログ, チャンク目録};

/// 衝突対象1件・子形状2件をどのチャンクにも同じ綴りで載せる。綴りが同じでも別のチャンクであれば重複にならない。
pub(crate) fn 静的物理形状を載せた世界を作る(
    名前: &str, 座標一覧: &[(i32, i32)]
) -> (Vec<PathBuf>, カタログ, チャンク目録) {
    let シーン = 静的シーンを作る(既定画素(), 0.2).静的物理形状を添える(建物1棟の形状を作る("酒場"));
    let (パス一覧, カタログ) = 生成物とカタログを作る(名前, "v1", 座標一覧, &シーン);
    (パス一覧, カタログ, 目録を作る(名前, 座標一覧))
}
