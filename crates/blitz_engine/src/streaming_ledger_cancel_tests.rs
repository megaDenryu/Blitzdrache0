#[test]
fn 読込中に不要になったcpuデータはgpuへ送らず破棄する() {
    let 候補集合 = 候補集合を作る(0.0, 0);
    let 座標 = 候補集合[0].要求().座標();
    let mut 台帳 = チャンク台帳::空を作る();
    assert!(台帳.必要集合を反映する(&候補集合).is_ok());
    assert_eq!(台帳.読込を開始する(座標), Ok(()));
    let Ok(差分) = 台帳.必要集合を反映する(&[]) else {
        panic!("空の必要集合を反映できなかった");
    };
    assert!(差分.解除要求一覧().is_empty());
    assert_eq!(台帳.準備完了を反映する(座標, 90), Ok(準備完了結果::CPUデータ破棄));
    assert_eq!(台帳.登録数(), 0);
}

/// 解除待ちの記録は再要求されても段階を戻さず、実破棄の報告で台帳から消えてから読み直す。
/// レンダラーの描画束は解除を予約した時点で取り消せないため、台帳だけが常駐へ戻ると描かれないまま常駐として数え、
/// そのあとに届く実破棄の報告が状態遷移不正になってアプリが終了する。
#[test]
fn 解除待ちの再要求は復帰せず実破棄のあとに読み直す() {
    let 候補集合 = 候補集合を作る(0.0, 0);
    let 座標 = 候補集合[0].要求().座標();
    let mut 台帳 = 常駐台帳を作る(&候補集合);
    assert!(台帳.必要集合を反映する(&[]).is_ok());
    assert_eq!(台帳.状態を引く(座標), Some(チャンク状態::解除待ち));
    let Ok(再要求差分) = 台帳.必要集合を反映する(&候補集合) else {
        panic!("再要求を反映できなかった");
    };
    assert!(再要求差分.読込要求一覧().is_empty());
    assert_eq!(台帳.状態を引く(座標), Some(チャンク状態::解除待ち));

    assert_eq!(台帳.gpu使用完了後に解除する(座標), Ok(()));
    assert_eq!(台帳.登録数(), 0);
    let Ok(読み直し差分) = 台帳.必要集合を反映する(&候補集合) else {
        panic!("実破棄のあとの再要求を反映できなかった");
    };
    assert_eq!(読み直し差分.読込要求一覧(), 要求一覧(&候補集合));
    assert_eq!(台帳.状態を引く(座標), Some(チャンク状態::読込待ち));
}

#[test]
fn 転送中に不要となったgpu資源は再要求されても解除待ちのまま残る() {
    let 候補集合 = 候補集合を作る(0.0, 0);
    let 座標 = 候補集合[0].要求().座標();
    let mut 台帳 = チャンク台帳::空を作る();
    assert!(台帳.必要集合を反映する(&候補集合).is_ok());
    assert_eq!(台帳.読込を開始する(座標), Ok(()));
    assert_eq!(台帳.準備完了を反映する(座標, 90), Ok(準備完了結果::GPU転送待ち));
    assert_eq!(台帳.gpu転送を開始する(座標), Ok(()));
    assert!(台帳.必要集合を反映する(&[]).is_ok());
    assert_eq!(台帳.gpu転送完了を反映する(座標), Ok(GPU転送完了結果::GPU資源解除待ち));
    assert!(台帳.必要集合を反映する(&候補集合).is_ok());
    assert_eq!(台帳.状態を引く(座標), Some(チャンク状態::解除待ち));
    assert!(matches!(
        台帳.フレーム境界で常駐化する(座標),
        Err(チャンク台帳エラー::状態遷移不正 { .. })
    ));
}

#[test]
fn 重複要求と順序違反を型付きエラーにする() {
    let 候補集合 = 候補集合を作る(0.0, 0);
    let 座標 = 候補集合[0].要求().座標();
    let mut 台帳 = チャンク台帳::空を作る();
    assert!(matches!(
        台帳.必要集合を反映する(&[候補集合[0], 候補集合[0]]),
        Err(チャンク台帳エラー::必要座標重複(_))
    ));
    assert!(台帳.必要集合を反映する(&候補集合).is_ok());
    assert!(matches!(
        台帳.フレーム境界で常駐化する(座標),
        Err(チャンク台帳エラー::状態遷移不正 { .. })
    ));
}

fn 常駐台帳を作る(候補集合: &[チャンク予算候補]) -> チャンク台帳 {
    let 座標 = 候補集合[0].要求().座標();
    let mut 台帳 = チャンク台帳::空を作る();
    assert!(台帳.必要集合を反映する(候補集合).is_ok());
    assert_eq!(台帳.読込を開始する(座標), Ok(()));
    assert_eq!(台帳.準備完了を反映する(座標, 90), Ok(準備完了結果::GPU転送待ち));
    assert_eq!(台帳.gpu転送を開始する(座標), Ok(()));
    assert_eq!(台帳.gpu転送完了を反映する(座標), Ok(GPU転送完了結果::フレーム反映待ち));
    assert_eq!(台帳.フレーム境界で常駐化する(座標), Ok(()));
    台帳
}
