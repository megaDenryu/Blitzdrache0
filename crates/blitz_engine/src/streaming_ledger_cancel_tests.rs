use crate::{
    GPU転送完了結果, streaming_ledger_tests::必要集合を作る, チャンク台帳, チャンク台帳エラー, チャンク状態, 準備完了結果
};

#[test]
fn 読込中に不要になったcpuデータはgpuへ送らず破棄する() {
    let 必要集合 = 必要集合を作る(0.0, 0);
    let 座標 = 必要集合[0].座標();
    let mut 台帳 = チャンク台帳::空を作る();
    assert!(台帳.必要集合を反映する(&必要集合).is_ok());
    assert_eq!(台帳.読込を開始する(座標), Ok(()));
    let Ok(差分) = 台帳.必要集合を反映する(&[]) else {
        panic!("空の必要集合を反映できなかった");
    };
    assert!(差分.解除要求一覧().is_empty());
    assert_eq!(台帳.準備完了を反映する(座標), Ok(準備完了結果::CPUデータ破棄));
    assert_eq!(台帳.登録数(), 0);
}

#[test]
fn gpu解除完了前の再要求は常駐を維持する() {
    let 必要集合 = 必要集合を作る(0.0, 0);
    let 座標 = 必要集合[0].座標();
    let mut 台帳 = 常駐台帳を作る(&必要集合);
    assert!(台帳.必要集合を反映する(&[]).is_ok());
    assert_eq!(台帳.状態を引く(座標), Some(チャンク状態::解除待ち));
    let Ok(差分) = 台帳.必要集合を反映する(&必要集合) else {
        panic!("再要求を反映できなかった");
    };
    assert!(差分.読込要求一覧().is_empty());
    assert_eq!(台帳.状態を引く(座標), Some(チャンク状態::常駐));
    assert!(matches!(台帳.gpu使用完了後に解除する(座標), Err(チャンク台帳エラー::状態遷移不正 { .. })));
}

#[test]
fn 転送中に不要となったgpu資源は解除待ちから反映待ちへ復帰できる() {
    let 必要集合 = 必要集合を作る(0.0, 0);
    let 座標 = 必要集合[0].座標();
    let mut 台帳 = チャンク台帳::空を作る();
    assert!(台帳.必要集合を反映する(&必要集合).is_ok());
    assert_eq!(台帳.読込を開始する(座標), Ok(()));
    assert_eq!(台帳.準備完了を反映する(座標), Ok(準備完了結果::GPU転送待ち));
    assert_eq!(台帳.gpu転送を開始する(座標), Ok(()));
    assert!(台帳.必要集合を反映する(&[]).is_ok());
    assert_eq!(台帳.gpu転送完了を反映する(座標), Ok(GPU転送完了結果::GPU資源解除待ち));
    assert!(台帳.必要集合を反映する(&必要集合).is_ok());
    assert_eq!(台帳.状態を引く(座標), Some(チャンク状態::フレーム反映待ち));
    assert_eq!(台帳.フレーム境界で常駐化する(座標), Ok(()));
}

#[test]
fn 重複要求と順序違反を型付きエラーにする() {
    let 必要集合 = 必要集合を作る(0.0, 0);
    let 座標 = 必要集合[0].座標();
    let mut 台帳 = チャンク台帳::空を作る();
    assert!(matches!(
        台帳.必要集合を反映する(&[必要集合[0], 必要集合[0]]),
        Err(チャンク台帳エラー::必要座標重複(_))
    ));
    assert!(台帳.必要集合を反映する(&必要集合).is_ok());
    assert!(matches!(
        台帳.フレーム境界で常駐化する(座標),
        Err(チャンク台帳エラー::状態遷移不正 { .. })
    ));
}

fn 常駐台帳を作る(必要集合: &[crate::チャンク要求]) -> チャンク台帳 {
    let 座標 = 必要集合[0].座標();
    let mut 台帳 = チャンク台帳::空を作る();
    assert!(台帳.必要集合を反映する(必要集合).is_ok());
    assert_eq!(台帳.読込を開始する(座標), Ok(()));
    assert_eq!(台帳.準備完了を反映する(座標), Ok(準備完了結果::GPU転送待ち));
    assert_eq!(台帳.gpu転送を開始する(座標), Ok(()));
    assert_eq!(台帳.gpu転送完了を反映する(座標), Ok(GPU転送完了結果::フレーム反映待ち));
    assert_eq!(台帳.フレーム境界で常駐化する(座標), Ok(()));
    台帳
}
