//! ストリーミング調停の起動時設定。世界の格子寸法と先読み範囲、保持してよいRAM・VRAMの上限を一組で渡す。

use blitz_math::大域メートル;

use super::memory_amount::ストリーミングメモリ量;

#[derive(Debug, Clone, Copy)]
pub struct ストリーミング調停設定 {
    /// チャンク1辺の大域メートル。検証用世界は100メートルである。
    pub 一辺: 大域メートル,
    /// 所属チャンクからのチェビシェフ距離で表す先読み範囲。0は所属チャンクだけを指す。
    pub 先読み半径: u8,
    pub 上限: ストリーミングメモリ量,
}
