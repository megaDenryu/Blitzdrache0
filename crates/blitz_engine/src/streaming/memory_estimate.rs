//! カタログの容量メタデータからチャンク1件の読込前見積量を作る。予算候補に付ける見積はこの経路だけが作る。
//! 参照: `_doc/設計/チャンクストリーミング.md`

use super::memory_amount::ストリーミングメモリ量;
use crate::asset::mesh_layout::{
    インデックス長, 個体別可視ID列長, 個体別置換検査記録長, 個体変換長, 個体配置長, 頂点長
};
use crate::アセットメタデータ;

#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum ストリーミング見積エラー {
    #[error("チャンクの見積バイト数をu64で表現できない")]
    バイト数超過,
}

/// RAMとVRAMは現時点で同じ合計になるが、ライフサイクルが別で将来のアラインメント要件や圧縮テクスチャで値が分かれるため別々に求める。
pub fn チャンクメモリ量を見積もる(
    メタデータ: アセットメタデータ,
) -> Result<ストリーミングメモリ量, ストリーミング見積エラー> {
    Ok(ストリーミングメモリ量::生成する(
        ram見積を作る(メタデータ)?,
        vram見積を作る(メタデータ)?,
    ))
}

/// RAMは頂点・インデックス・展開済みテクスチャと、インスタンス群の個体配置に、描画側が個体ごとに持つ置換検査の記録を足した量である。
/// 検査の記録だけは寿命が違い、束の読込時に確保されて常駐のあいだ残る。それでも読込前の見積へ数えるのは、
/// 収容を決める地点がここしかなく、数えなければ個体数の多いチャンクほど系統的に過小な見積で収容を決めることになるためである。
fn ram見積を作る(メタデータ: アセットメタデータ) -> Result<u64, ストリーミング見積エラー> {
    let 幾何 = 幾何とテクスチャを合計する(メタデータ)?;
    let 個体あたり = 個体配置長
        .checked_add(個体別置換検査記録長)
        .ok_or(ストリーミング見積エラー::バイト数超過)?;
    let 個体資源 = 要素バイト数を求める(メタデータ.個体数, 個体あたり)?;
    幾何.checked_add(個体資源).ok_or(ストリーミング見積エラー::バイト数超過)
}

/// VRAMは常駐中のGPU資源であり、頂点バッファ・インデックスバッファ・テクスチャと、インスタンス群の個体変換バッファ、
/// および同じく束の読込時に確保して常駐する可視ID列バッファを含む。可視ID列を数えないと、個体数の多いチャンクほど
/// 系統的に過小な見積で収容を決めることになる。
fn vram見積を作る(メタデータ: アセットメタデータ) -> Result<u64, ストリーミング見積エラー> {
    let 幾何 = 幾何とテクスチャを合計する(メタデータ)?;
    let 個体あたり = 個体変換長.checked_add(個体別可視ID列長).ok_or(ストリーミング見積エラー::バイト数超過)?;
    let 個体資源 = 要素バイト数を求める(メタデータ.個体数, 個体あたり)?;
    幾何.checked_add(個体資源).ok_or(ストリーミング見積エラー::バイト数超過)
}

fn 幾何とテクスチャを合計する(メタデータ: アセットメタデータ) -> Result<u64, ストリーミング見積エラー> {
    let 頂点バイト数 = 要素バイト数を求める(メタデータ.頂点数, 頂点長)?;
    let インデックスバイト数 = 要素バイト数を求める(メタデータ.インデックス数, インデックス長)?;
    頂点バイト数
        .checked_add(インデックスバイト数)
        .and_then(|小計| 小計.checked_add(メタデータ.テクスチャバイト数))
        .ok_or(ストリーミング見積エラー::バイト数超過)
}

fn 要素バイト数を求める(件数: u64, 要素バイト長: usize) -> Result<u64, ストリーミング見積エラー> {
    let 要素バイト長 = u64::try_from(要素バイト長).map_err(|_| ストリーミング見積エラー::バイト数超過)?;
    件数.checked_mul(要素バイト長).ok_or(ストリーミング見積エラー::バイト数超過)
}
