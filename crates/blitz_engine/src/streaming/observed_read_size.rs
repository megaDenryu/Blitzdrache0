//! 読込器が返したチャンクごとの読込量を覚え、同じ座標が再び予算候補になったときの見積を押し上げる保管。
//! カタログ由来の見積はメッシュとテクスチャの生バイト数だけを数えるのに対し、観測は版付きファイル全体の長さであるため、見積は系統的に小さい。
//! 覚えないと「上限を超えたので退避する、見積では収まるので再び収容する、観測でまた上限を超える」という往復が続く。
//! 注意: 観測はファイル長の代理指標であり、デシリアライズ後のヒープ常駐量へは置き換えない。OW3の検証用地形世界では見積との差が1.0004倍以内であり、大きく乖離するのはテスト専用の盤面世界だけである。
//! 参照: `_doc/設計/チャンクストリーミング.md`「見積量とRAM・VRAMの区別」「検証用地形世界」

use std::collections::HashMap;

use crate::チャンク座標;

use super::memory_amount::ストリーミングメモリ量;

#[derive(Debug)]
pub struct 観測済み読込量 {
    座標ごとの読込量: HashMap<チャンク座標, u64>,
}

impl 観測済み読込量 {
    pub fn 空を作る() -> Self {
        Self {
            座標ごとの読込量: HashMap::new(),
        }
    }

    /// 読込器が返した読込量を覚える。同じ座標を読み直したときは新しい観測で上書きする。
    pub fn 記録する(&mut self, 座標: チャンク座標, 読込バイト数: u64) {
        self.座標ごとの読込量.insert(座標, 読込バイト数);
    }

    /// 観測を覚えている座標のRAM見積を、カタログの見積と観測の大きいほうへそろえる。
    /// 観測が見積より小さい座標で無条件に置き換えると、カタログが数えている分を取りこぼして過小計上へ戻るためである。
    /// VRAMは観測を持たないため見積のままにする。
    pub fn 見積を補正する(&self, 座標: チャンク座標, 見積: ストリーミングメモリ量) -> ストリーミングメモリ量 {
        match self.座標ごとの読込量.get(&座標) {
            Some(観測) => ストリーミングメモリ量::生成する(見積.ramバイト数.max(*観測), 見積.vramバイト数),
            None => 見積,
        }
    }

    pub fn 件数(&self) -> usize {
        self.座標ごとの読込量.len()
    }
}
