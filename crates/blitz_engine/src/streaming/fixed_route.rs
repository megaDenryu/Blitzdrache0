//! 始点と終点のあいだを一定速度で往復する固定経路。フレーム番号だけからプレイヤーの大域位置を決める。
//! 実時間へ追従しないのは、同じフレーム番号から同じ位置を得て読込順と解除順を実行のたびに再現するためである。
//! 参照: `_doc/設計/チャンクストリーミング.md`「固定経路の自動移動」

use blitz_math::{大域メートル, 大域ワールド位置};

use super::fixed_route_error::固定経路エラー;

#[derive(Debug, Clone, Copy)]
pub struct 固定経路 {
    始点: 大域ワールド位置,
    終点: 大域ワールド位置,
    一フレーム移動量: 大域メートル,
    全長メートル: f64,
}

impl 固定経路 {
    pub fn 生成する(
        始点: 大域ワールド位置, 終点: 大域ワールド位置, 一フレーム移動量: 大域メートル
    ) -> Result<Self, 固定経路エラー> {
        if !端点が有限か(始点) || !端点が有限か(終点) {
            return Err(固定経路エラー::端点非有限);
        }
        let 移動量 = 一フレーム移動量.値();
        if !移動量.is_finite() || 移動量 <= 0.0 {
            return Err(固定経路エラー::移動量不正);
        }
        let 全長メートル = 距離を求める(始点, 終点);
        if 全長メートル <= 0.0 {
            return Err(固定経路エラー::端点一致);
        }
        Ok(Self {
            始点,
            終点,
            一フレーム移動量,
            全長メートル,
        })
    }

    /// フレーム番号ぶん進んだ位置。終点に達したら折り返し、始点に戻ったらまた終点へ向かう三角波である。
    pub fn 位置を求める(&self, フレーム番号: u32) -> 大域ワールド位置 {
        let 進行メートル = self.進行を求める(フレーム番号);
        let 比 = 進行メートル / self.全長メートル;
        大域ワールド位置::生成する(
            軸を補間する(self.始点.x(), self.終点.x(), 比),
            軸を補間する(self.始点.y(), self.終点.y(), 比),
            軸を補間する(self.始点.z(), self.終点.z(), 比),
        )
    }

    /// 始点からの道のり。往復1周は全長の2倍であり、折返し後は残りの位相ぶん戻る。
    fn 進行を求める(&self, フレーム番号: u32) -> f64 {
        let 周期メートル = self.全長メートル * 2.0;
        let 位相 = (self.一フレーム移動量.値() * f64::from(フレーム番号)).rem_euclid(周期メートル);
        if 位相 <= self.全長メートル {
            位相
        } else {
            周期メートル - 位相
        }
    }
}

fn 端点が有限か(位置: 大域ワールド位置) -> bool {
    位置.x().値().is_finite() && 位置.y().値().is_finite() && 位置.z().値().is_finite()
}

fn 距離を求める(始点: 大域ワールド位置, 終点: 大域ワールド位置) -> f64 {
    let x差 = (終点.x() - 始点.x()).値();
    let y差 = (終点.y() - 始点.y()).値();
    let z差 = (終点.z() - 始点.z()).値();
    x差.mul_add(x差, y差.mul_add(y差, z差 * z差)).sqrt()
}

fn 軸を補間する(始: 大域メートル, 終: 大域メートル, 比: f64) -> 大域メートル {
    始 + (終 - 始) * 比
}
