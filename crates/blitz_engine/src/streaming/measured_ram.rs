//! 読込で得たチャンクごとのRAM実測バイト数を覚え、同じ座標が再び予算候補になったときの見積を実測へ置き換える保管。
//! カタログ由来の見積はメッシュとテクスチャの生バイト数だけを数えるのに対し、実測は版付きファイル全体の長さであるため、見積は系統的に小さい。
//! 覚えないと「上限を超えたので退避する、見積では収まるので再び収容する、実測で再び上限を超える」という往復が続く。
//! 注意: 台帳から記録が消えても記憶は消さない。再訪したときの見積精度がこの保管の目的である。
//! 参照: `_doc/設計/チャンクストリーミング.md`「メモリ予算と縮退」

use std::collections::HashMap;

use crate::チャンク座標;

use super::memory_amount::ストリーミングメモリ量;

#[derive(Debug)]
pub struct チャンクRAM実測記憶 {
    実測ramバイト数: HashMap<チャンク座標, u64>,
}

impl チャンクRAM実測記憶 {
    pub fn 空を作る() -> Self {
        Self {
            実測ramバイト数: HashMap::new(),
        }
    }

    /// 読込器が返した実測を覚える。同じ座標を読み直したときは新しい実測で上書きする。
    pub fn 記録する(&mut self, 座標: チャンク座標, ramバイト数: u64) {
        self.実測ramバイト数.insert(座標, ramバイト数);
    }

    /// 実測を覚えている座標はRAMの見積を実測へ置き換える。VRAMは実測を持たないため見積のままにする。
    pub fn 見積を補正する(&self, 座標: チャンク座標, 見積: ストリーミングメモリ量) -> ストリーミングメモリ量 {
        match self.実測ramバイト数.get(&座標) {
            Some(実測) => ストリーミングメモリ量::生成する(*実測, 見積.vramバイト数),
            None => 見積,
        }
    }

    pub fn 件数(&self) -> usize {
        self.実測ramバイト数.len()
    }
}
