//! 読込要求の解決、キュー投入、ワーカースレッドの失敗。

use crate::アセットID;

#[derive(Debug, thiserror::Error)]
pub enum チャンク読込エラー {
    #[error("カタログに未登録のアセットID: {0}")]
    カタログ未登録(アセットID),
    #[error("チャンク読込要求キューが満杯である")]
    要求キュー満杯,
    #[error("チャンク読込ワーカーが停止している")]
    ワーカー停止,
    #[error("チャンク読込ワーカーを起動できない: {0}")]
    ワーカー起動失敗(String),
}
