//! 予算内へ収容した接頭辞と、外周側を除外した縮退理由。
//!
//! `使用量超過による退避`は、読込前の見積が観測より小さいために、見積で収容を決めた集合が読込完了後に上限を超えたときの判定である。予算はこの状態を入力エラーとして拒むため、調停は予算を適用せずこの判定を作る。その`退避一覧`は上限超過を解く分を中心から遠い順に置き、同じフレームで近い未収容チャンクへ余地を作る分があればその後ろへ続ける。中心チャンクは退避しないため、中心だけで上限を超えると`退避後も超過`が真になる。
//! `使用量超過による退避`が起こるのは、上限超過のため新規収容をせず、遠方の常駐を解除待ちへ退避させたフレームである。
//! `優先度退避`が起こるのは、上限内だが、より近い未収容チャンクの収容余地を作って退避させたフレームである。
//! `優先度退避`は、使用量が上限内でも、除外された最も近い未収容チャンクより遠い常駐チャンクがあるときにその収容余地を作る判定である。退避は予約であり、解除待ちは実破棄が報告されるまでVRAMを数え続けるため、`最初の除外`が実際に収容されるのは実破棄を経た後続フレームである。その`退避一覧`は中心から遠い順である。

use crate::チャンク座標;

use super::{memory_amount::ストリーミングメモリ量, memory_candidate::チャンク予算候補};

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 予算判定 {
    全件収容,
    縮退 {
        最初の除外: チャンク座標,
        ram超過: bool,
        vram超過: bool,
    },
    使用量超過による退避 {
        退避一覧: Vec<チャンク座標>, // 退避させた座標を退避した順に並べたもの
        退避後も超過: bool,          // 解除後の見込み使用量が上限以下へ戻らなかったか
    },
    優先度退避 {
        最初の除外: チャンク座標,    // 収容を待っている最も近い未収容チャンク
        退避一覧: Vec<チャンク座標>, // 退避させた座標を退避した順に並べたもの
    },
}

/// 収容一覧は見積量を保った候補を返す。台帳へ登録するときに見積量が必要であり、呼び出し側が同じ見積を二度引かないためである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ストリーミング予算結果 {
    pub(super) 収容一覧: Vec<チャンク予算候補>,
    pub(super) 除外一覧: Vec<チャンク座標>,
    pub(super) 使用量: ストリーミングメモリ量,
    pub(super) 判定: 予算判定,
}

impl ストリーミング予算結果 {
    pub fn 収容一覧(&self) -> &[チャンク予算候補] {
        &self.収容一覧
    }
    pub fn 除外一覧(&self) -> &[チャンク座標] {
        &self.除外一覧
    }
    pub fn 使用量(&self) -> ストリーミングメモリ量 {
        self.使用量
    }
    pub fn 判定(&self) -> &予算判定 {
        &self.判定
    }
}
