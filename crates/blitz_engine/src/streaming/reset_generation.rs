//! リセットのたびに進む世代番号。読込ジョブと完了通知が同じ値を運び、リセット前に投入した読込の完了が
//! 座標一致だけでリセット後の読込の完了として受理されるのを防ぐ。
//! 前進は`次を作る`だけで行い、u64を超えたら値なしを返す。飽和も折り返しもしない。
//! 参照: `_doc/設計/チャンクストリーミング.md`「ホットリロードとの併用」

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct リセット世代(u64);

impl リセット世代 {
    /// リセットを一度も行っていない状態の世代。
    pub fn 最初を作る() -> Self {
        Self(0)
    }

    /// 次の世代。u64を超えたら値なしを返し、呼出し側が型付きエラーへ変える。
    pub fn 次を作る(self) -> Option<Self> {
        self.0.checked_add(1).map(Self)
    }
}
