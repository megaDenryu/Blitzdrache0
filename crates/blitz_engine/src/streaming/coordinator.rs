//! ストリーミング調停: プレイヤーの大域位置から必要チャンク集合を決め、目録とカタログで解決し、予算で縮退させ、台帳と読込器を1フレーム分進める手続きを所有する。
//! 格子・目録・予算・台帳・読込器を内部へ閉じるのは、台帳の状態が「格子が出した必要集合を目録が解決し予算が縮退させた結果」でなければならないという不変条件を共有するためである。個別に持たせると、この手続きを経ずに台帳だけを更新する経路が開く。
//! 参照: `_doc/設計/チャンクストリーミング.md`

mod candidates;
mod degradation;
mod prepared_data;

use std::collections::HashMap;

use blitz_math::大域ワールド位置;

use super::{
    chunk_directory::チャンク目録,
    chunk_grid::チャンク格子,
    chunk_ledger::チャンク台帳,
    chunk_request::チャンク要求,
    coordinator_error::ストリーミング調停エラー,
    coordinator_progress::ストリーミング進行,
    coordinator_settings::ストリーミング調停設定,
    loader::{チャンク読込エラー, チャンク読込器},
    memory_budget::ストリーミング予算,
};
use crate::{カタログ, シーンデータ, チャンク座標};

pub struct ストリーミング調停 {
    格子: チャンク格子,
    目録: チャンク目録,
    予算: ストリーミング予算,
    台帳: チャンク台帳,
    読込器: チャンク読込器,
    先読み半径: u8,
    /// 準備済みチャンクのCPUデータ。台帳が準備済みとして数えるRAMはこの保管の実体である。出入りは`prepared_data`が所有する。
    準備済みシーン: HashMap<チャンク座標, シーンデータ>,
}

impl ストリーミング調停 {
    /// 読込ワーカースレッドの起動を伴い失敗しうるため、生成をコンストラクタでなく結果を返す関数で行う。
    pub fn 起動する(設定: ストリーミング調停設定, 目録: チャンク目録) -> Result<Self, ストリーミング調停エラー> {
        Ok(Self {
            格子: チャンク格子::生成する(設定.一辺)?,
            目録,
            予算: ストリーミング予算::生成する(設定.上限)?,
            台帳: チャンク台帳::空を作る(),
            読込器: チャンク読込器::起動する()?,
            先読み半径: 設定.先読み半径,
            準備済みシーン: HashMap::new(),
        })
    }

    /// プレイヤーの大域位置を受け取り、そのフレームで実際に起きた読込・準備完了・解除と予算判定を返す。
    pub fn 一フレーム進める(
        &mut self,
        プレイヤー位置: 大域ワールド位置,
        カタログ: &カタログ,
    ) -> Result<ストリーミング進行, ストリーミング調停エラー> {
        let 要求一覧 = self.格子.必要集合を計算する(プレイヤー位置, self.先読み半径)?;
        let 解決済み一覧 = candidates::目録とカタログで解決する(&self.目録, カタログ, &要求一覧)?;
        let (判定, 反映集合) = degradation::予算で縮退させる(self.予算, &self.台帳, 解決済み一覧)?;
        let 差分 = self.台帳.必要集合を反映する(&反映集合)?;
        let 読込開始一覧 = self.読込を投入する(差分.読込要求一覧(), カタログ)?;
        let mut cpuデータ破棄一覧 = self.不要なcpuデータを捨てる();
        let 準備完了一覧 = self.完了を回収する(&mut cpuデータ破棄一覧)?;
        Ok(ストリーミング進行 {
            読込開始一覧,
            準備完了一覧,
            cpuデータ破棄一覧,
            gpu資源解除待ち一覧: 差分.解除要求一覧().to_vec(),
            使用量: self.台帳.現在使用量を導出する()?,
            台帳登録数: self.台帳.登録数(),
            判定,
        })
    }

    fn 読込を投入する(
        &mut self,
        読込要求一覧: &[チャンク要求],
        カタログ: &カタログ,
    ) -> Result<Vec<チャンク座標>, ストリーミング調停エラー> {
        let mut 開始一覧 = Vec::new();
        for 要求 in 読込要求一覧 {
            let 座標 = 要求.座標();
            let アセット = self.目録.アセットを引く(座標).ok_or(ストリーミング調停エラー::目録解決不整合(座標))?;
            match self.読込器.読込を要求する(座標, アセット, カタログ) {
                Ok(()) => {}
                // 満杯なら次フレームで再試行する。中心優先の投入順を崩さないため、以降の要求も今フレームは投入しない。
                Err(チャンク読込エラー::要求キュー満杯) => break,
                Err(誤り) => return Err(誤り.into()),
            }
            self.台帳.読込を開始する(座標)?;
            開始一覧.push(座標);
        }
        Ok(開始一覧)
    }
}
