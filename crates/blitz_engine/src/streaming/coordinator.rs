//! ストリーミング調停: プレイヤーの大域位置から必要チャンク集合を決め、目録とカタログで解決し、予算で縮退させ、台帳と読込器を1フレーム分進める手続きを所有する。
//! 格子・目録・予算・台帳・読込器を内部へ閉じるのは、台帳の状態が「格子が出した必要集合を目録が解決し予算が縮退させた結果」でなければならないという不変条件を共有するためである。個別に持たせると、この手続きを経ずに台帳だけを更新する経路が開く。
//! 参照: `_doc/設計/チャンクストリーミング.md`

