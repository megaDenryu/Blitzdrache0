use blitz_math::大域ワールド位置;

use generation::世代状態;

use super::{
    chunk_directory::チャンク目録, chunk_grid::チャンク格子, chunk_ledger::チャンク台帳, coordinator_error::ストリーミング調停エラー,
    coordinator_progress::ストリーミング進行, coordinator_settings::ストリーミング調停設定, eviction_hysteresis::退避優位計数,
    loader::チャンク読込器, memory_budget::ストリーミング予算, observed_read_size::観測済み読込量, transfer_total::ストリーミング転送量,
};
use crate::{カタログ, シーンデータ, チャンク座標};

pub struct ストリーミング調停 {
    格子: チャンク格子,
    目録: チャンク目録,
    予算: ストリーミング予算,
    台帳: チャンク台帳,
    読込器: チャンク読込器,
    先読み半径: u8,
    /// 準備済みチャンクのCPUデータ。台帳が準備済みとして数えるRAMはこの保管の実体である。読込完了での投入と不要時の破棄は`prepared_data`が、GPU転送のための取り出しは`gpu_handoff`が所有する。
    準備済みシーン: HashMap<チャンク座標, シーンデータ>,
    /// 読込で得た読込量の観測。予算候補の見積をここで押し上げ、見積の過小によるスラッシングを止める。
    観測済み読込量: 観測済み読込量,
    /// 近い未収容チャンクのための退避が、同じ座標について何フレーム続けて優位だったかの計数。境界の往復で退避が起きないようにする。
    優位計数: 退避優位計数,
    /// リセットのたびに進む世代。投入した読込と返ってきた完了が同じ値を持つかで、リセット前の完了を退ける。
    世代: 世代状態,
    転送量: ストリーミング転送量,
}

impl ストリーミング調停 {
    /// 読込ワーカースレッドの起動を伴い失敗しうるため、生成をコンストラクタでなく結果を返す関数で行う。
    pub fn 起動する(設定: ストリーミング調停設定, 目録: チャンク目録) -> Result<Self, ストリーミング調停エラー> {
        let 一辺 = 目録.一辺();
        Ok(Self {
            格子: チャンク格子::生成する(一辺.大域メートルへ変換する())?,
            目録,
            予算: ストリーミング予算::生成する(設定.上限)?,
            台帳: チャンク台帳::空を作る(),
            読込器: チャンク読込器::起動する(設定.読込)?,
            先読み半径: 設定.先読み半径,
            準備済みシーン: HashMap::new(),
            観測済み読込量: 観測済み読込量::空を作る(),
            優位計数: 退避優位計数::空を作る(),
            世代: 世代状態::最初を作る(),
            転送量: ストリーミング転送量::default(),
        })
    }

    /// 常駐しているチャンクの座標を受け皿へ集める。地形LODの選択が対象にできるのは常駐しているチャンクだけであり、その集合を持つのは台帳であるためここが仲介する。
    pub fn 常駐座標を集める(&self, 受け皿: &mut Vec<チャンク座標>) {
        self.台帳.常駐座標を集める(受け皿);
    }

    /// プレイヤーの大域位置を受け取り、そのフレームで実際に起きた読込・準備完了・解除と予算判定を返す。
    pub fn 一フレーム進める(
        &mut self,
        プレイヤー位置: 大域ワールド位置,
        カタログ: &カタログ,
    ) -> Result<ストリーミング進行, ストリーミング調停エラー> {
        let 世代 = self.世代.現在()?;
        let 中心 = self.格子.所属座標を求める(プレイヤー位置)?;
        let 要求一覧 = self.格子.必要集合を計算する(プレイヤー位置, self.先読み半径)?;
        let 解決済み一覧 = candidates::目録とカタログで解決する(&self.目録, カタログ, &self.観測済み読込量, &要求一覧)?;
        let (判定, 差分) = degradation::必要集合を確定させる(self.予算, &mut self.台帳, 中心, &mut self.優位計数, 解決済み一覧)?;
        let 読込開始一覧 = self.読込を投入する(差分.読込要求一覧(), カタログ, 世代)?;
        let mut cpuデータ破棄一覧 = self.不要なcpuデータを捨てる();
        let 準備完了一覧 = self.完了を回収する(&mut cpuデータ破棄一覧, 世代)?;
        Ok(ストリーミング進行 {
            読込開始一覧,
            準備完了一覧,
            cpuデータ破棄一覧,
            gpu資源解除待ち一覧: 差分.解除要求一覧().to_vec(),
            使用量: self.台帳.現在使用量を導出する()?,
            台帳登録数: self.台帳.登録数(),
            判定,
        })
    }
}
