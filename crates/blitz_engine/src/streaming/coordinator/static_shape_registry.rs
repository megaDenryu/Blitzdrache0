//! 読込済みチャンクの静的物理形状を外から読む口を所有する。触れるのは`静的物理形状の保管`だけである。
//!
//! 注意: 形状の公開区間はチャンクの描画区間を必ず包含する。CPU読込完了から実破棄までが公開区間であり、描画はその内側で始まり終わる。
//! 描かれているのに当たらない瞬間を作らないためであり、当たるのに描かれていない余白は安全側として許す。
//!
//! 出入りを決めるのはここではない。読込完了で載せるのは`prepared_data`、CPUデータの破棄で外すのも`prepared_data`、
//! GPU資源の解除で外すのは`gpu_handoff`、まとめて捨てるのは`reset`である。ここは読むだけであり、
//! 公開区間が描画区間を包含することは出入りの側が守る。
//!
//! 呼び出しタイミング: 世界の形への問い合わせが、当たりを調べたいチャンクごとに読む。1フレームに何度も呼ばれうる。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断12: 空間探索は粗い候補選別と詳細判定を責務として分け、世界は二段構えで辿る」

use super::ストリーミング調停;

use crate::static_shape::チャンクの静的物理形状;
use crate::チャンク座標;

impl ストリーミング調停 {
    /// そのチャンクの静的物理形状。読み込まれていない座標には値なしを返す。
    /// 値なしと「形状が0件のチャンク」は別物であり、前者は答えられないこと、後者は当たる物が無いことを表す。
    pub fn 静的物理形状を引く(&self, 座標: チャンク座標) -> Option<&チャンクの静的物理形状> {
        self.静的物理形状の保管.座標で引く(座標)
    }

    /// 静的物理形状を持っているチャンクの件数。読込で増え解除で減ることを呼出し側と試験が確かめられるようにする。
    pub fn 静的物理形状を持つチャンク数(&self) -> usize {
        self.静的物理形状の保管.登録数()
    }
}
