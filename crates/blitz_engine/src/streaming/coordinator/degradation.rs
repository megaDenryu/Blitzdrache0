//! 解決済みの候補一覧を予算へ通し、今フレームの判定と、台帳へ反映してよい必要集合を作る工程。
//! 受け取るのは中心優先の解決済み候補一覧、返すのは予算判定と反映集合である。
//! 予算へ渡す候補は台帳にまだ無い新規分だけにする。既存記録が持つ資源は台帳が導出する現在使用量に既に入っており、候補にも入れると同じ資源を二度数えて必要集合が不当に縮むためである。

use std::collections::HashSet;

use crate::streaming::{
    chunk_ledger::チャンク台帳, coordinator_error::ストリーミング調停エラー, memory_budget::ストリーミング予算, memory_candidate::チャンク予算候補,
    memory_result::予算判定,
};

pub(super) fn 予算で縮退させる(
    予算: ストリーミング予算,
    台帳: &チャンク台帳,
    解決済み一覧: Vec<チャンク予算候補>,
) -> Result<(予算判定, Vec<チャンク予算候補>), ストリーミング調停エラー> {
    let 新規候補: Vec<_> = 解決済み一覧
        .iter()
        .copied()
        .filter(|候補| 台帳.状態を引く(候補.要求().座標()).is_none())
        .collect();
    let 結果 = 予算.適用する(台帳.現在使用量を導出する()?, &新規候補)?;
    let 収容集合: HashSet<_> = 結果.収容一覧().iter().map(|候補| 候補.要求().座標()).collect();
    let 反映集合 = 解決済み一覧
        .into_iter()
        .filter(|候補| {
            let 座標 = 候補.要求().座標();
            収容集合.contains(&座標) || 台帳.状態を引く(座標).is_some()
        })
        .collect();
    Ok((結果.判定(), 反映集合))
}
