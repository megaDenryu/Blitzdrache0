//! 解決済みの候補一覧から今フレームの必要集合を台帳へ確定させる工程。受け取るのは中心優先の解決済み候補一覧と必要集合の中心、
//! 返すのは予算判定と台帳が出した集合差分である。収容と退避のどちらへ倒すかの分岐をここが持つ。
//! 予算へ渡す候補は台帳にまだ無い新規分だけにする。既存記録が持つ資源は台帳が導出する現在使用量に既に入っており、候補にも入れると同じ資源を二度数えて必要集合が不当に縮むためである。

use std::collections::HashSet;

use crate::streaming::{
    chunk_diff::チャンク集合差分, chunk_ledger::チャンク台帳, coordinator_error::ストリーミング調停エラー, memory_budget::ストリーミング予算,
    memory_candidate::チャンク予算候補, memory_result::予算判定,
};
use crate::チャンク座標;

pub(super) fn 必要集合を確定させる(
    予算: ストリーミング予算,
    台帳: &mut チャンク台帳,
    中心: チャンク座標,
    解決済み一覧: Vec<チャンク予算候補>,
) -> Result<(予算判定, チャンク集合差分), ストリーミング調停エラー> {
    let 現在使用量 = 台帳.現在使用量を導出する()?;
    if 予算.上限を超えるか(現在使用量) {
        return 退避へ倒す(予算, 台帳, 中心, 解決済み一覧);
    }
    let 新規候補: Vec<_> = 解決済み一覧
        .iter()
        .copied()
        .filter(|候補| 台帳.状態を引く(候補.要求().座標()).is_none())
        .collect();
    let 結果 = 予算.適用する(現在使用量, &新規候補)?;
    let 収容集合: HashSet<_> = 結果.収容一覧().iter().map(|候補| 候補.要求().座標()).collect();
    let 反映集合: Vec<_> = 解決済み一覧
        .into_iter()
        .filter(|候補| {
            let 座標 = 候補.要求().座標();
            収容集合.contains(&座標) || 台帳.状態を引く(座標).is_some()
        })
        .collect();
    let 差分 = 台帳.必要集合を反映する(&反映集合)?;
    Ok((結果.判定().clone(), 差分))
}

/// 現在使用量が上限を超えているフレームは予算を適用しない。予算はこの状態を入力エラーとして拒み、握り潰さない限り以降のフレームでも同じ失敗を繰り返すためである。
/// 新規収容をせず、既に台帳にある座標だけを必要のまま反映してから退避する。反映より先に退避すると、必要のまま残る座標が解除待ちから常駐へ復帰して退避が打ち消される。
fn 退避へ倒す(
    予算: ストリーミング予算,
    台帳: &mut チャンク台帳,
    中心: チャンク座標,
    解決済み一覧: Vec<チャンク予算候補>,
) -> Result<(予算判定, チャンク集合差分), ストリーミング調停エラー> {
    let 反映集合: Vec<_> = 解決済み一覧
        .into_iter()
        .filter(|候補| 台帳.状態を引く(候補.要求().座標()).is_some())
        .collect();
    let mut 差分 = 台帳.必要集合を反映する(&反映集合)?;
    let 退避 = 台帳.上限超過から退避する(中心, 予算.上限())?;
    差分.解除要求を足す(退避.退避一覧());
    let 判定 = 予算判定::使用量超過による退避 {
        退避一覧: 退避.退避一覧().to_vec(),
        退避後も超過: 退避.退避後も超過(),
    };
    Ok((判定, 差分))
}
