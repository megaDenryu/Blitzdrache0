//! 解決済みの候補一覧から今フレームの必要集合を台帳へ確定させる工程。受け取るのは中心優先の解決済み候補一覧と必要集合の中心、返すのは予算判定と台帳が出した集合差分である。
//! 収容と退避のどちらへ倒すかの分岐をここが持つ。使用量が上限を超えたフレームの扱いは`overuse_eviction`が持つ。
//! 予算へ渡す候補は台帳にまだ無い新規分だけにする。既存記録が持つ資源は台帳が導出する現在使用量に既に入っており、候補にも入れると同じ資源を二度数えて必要集合が不当に縮むためである。

use std::collections::HashSet;

use super::{overuse_eviction, priority_eviction};

use crate::streaming::{
    chunk_diff::チャンク集合差分,
    chunk_ledger::チャンク台帳,
    coordinator_error::ストリーミング調停エラー,
    eviction_hysteresis::退避優位計数,
    memory_budget::ストリーミング予算,
    memory_candidate::チャンク予算候補,
    memory_result::{ストリーミング予算結果, 予算判定},
};
use crate::チャンク座標;

pub(super) fn 必要集合を確定させる(
    予算: ストリーミング予算,
    台帳: &mut チャンク台帳,
    中心: チャンク座標,
    優位計数: &mut 退避優位計数,
    解決済み一覧: Vec<チャンク予算候補>,
) -> Result<(予算判定, チャンク集合差分), ストリーミング調停エラー> {
    let 現在使用量 = 台帳.現在使用量を導出する()?;
    if 予算.上限を超えるか(現在使用量) {
        return overuse_eviction::退避へ倒す(予算, 台帳, 中心, 優位計数, 解決済み一覧);
    }
    let 新規候補: Vec<_> = 解決済み一覧
        .iter()
        .copied()
        .filter(|候補| 台帳.状態を引く(候補.要求().座標()).is_none())
        .collect();
    let 結果 = 予算.適用する(現在使用量, &新規候補)?;
    let 収容集合: HashSet<_> = 結果.収容一覧().iter().map(|候補| 候補.要求().座標()).collect();
    let 反映集合: Vec<_> = 解決済み一覧
        .into_iter()
        .filter(|候補| {
            let 座標 = 候補.要求().座標();
            収容集合.contains(&座標) || 台帳.状態を引く(座標).is_some()
        })
        .collect();
    let mut 差分 = 台帳.必要集合を反映する(&反映集合)?;
    let 未収容の先頭 = 最初の除外候補(&新規候補, &結果);
    let 退避一覧 = priority_eviction::収容余地を作る(台帳, 中心, 優位計数, 予算.上限(), 未収容の先頭, &[])?;
    台帳.退避を適用する(&退避一覧)?;
    差分.解除要求を足す(&退避一覧);
    Ok((判定を選ぶ(結果.判定().clone(), 未収容の先頭, 退避一覧), 差分))
}

/// 予算は最初に収まらない候補から後ろをすべて除外するため、除外一覧の先頭が最も近い未収容チャンクである。
fn 最初の除外候補(新規候補: &[チャンク予算候補], 結果: &ストリーミング予算結果) -> Option<チャンク予算候補> {
    let 座標 = 結果.除外一覧().first().copied()?;
    新規候補.iter().copied().find(|候補| 候補.要求().座標() == 座標)
}

/// 退避が1件でも起きたフレームは、予算そのものの判定でなく退避の判定を返す。呼出し側が退避の有無を判定だけで見分けられるようにするためである。
fn 判定を選ぶ(
    予算の判定: 予算判定, 未収容の先頭: Option<チャンク予算候補>, 退避一覧: Vec<チャンク座標>
) -> 予算判定 {
    match 未収容の先頭 {
        Some(候補) if !退避一覧.is_empty() => 予算判定::優先度退避 {
            最初の除外: 候補.要求().座標(),
            退避一覧,
        },
        _ => 予算の判定,
    }
}
