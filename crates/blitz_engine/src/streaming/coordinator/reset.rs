//! 実行時アセット一式を差し替えるときの調停のリセットを所有する。何を捨てて何を残すかの規則と、その結果を外から確かめる読み取りをここが持つ。
//! 呼び出しタイミング: 呼び出し側が旧世界のチャンク描画束を解除した後、新しいチャンク目録を採用するときに1回だけ呼ぶ。
//! 参照: `_doc/設計/チャンクストリーミング.md`「ホットリロードとの併用」

use super::ストリーミング調停;

use crate::streaming::{chunk_ledger::チャンク台帳, observed_read_size::観測済み読込量};

impl ストリーミング調停 {
    /// 台帳と準備済みCPUデータの保管を空にし、読込量の観測も捨てて、次のフレームから読み直させる。
    /// 観測を捨てるのは、リセットが起きるのがアセットの内容が変わったときであり、変わった瞬間に古い観測が実体と食い違うためである。
    /// 転送量は残す。過ぎ去った事象の累計であり、アセットが変わっても遡って変わらないからである。
    /// 読込器も残す。ワーカースレッドを起動し直す理由がなく、リセット前に投入した読込の完了は`完了を回収する`が破棄として片付ける。
    /// 世代を進めるのは、同じ座標を読み直したときに古い内容の完了を新しい読込の完了として受理させないためである。
    /// 進められないほど世代が溢れた場合は、次に1フレーム進めるときへ型付きエラーとして持ち越す(`generation`)。
    pub fn リセットする(&mut self) {
        self.台帳 = チャンク台帳::空を作る();
        self.準備済みシーン.clear();
        self.観測済み読込量 = 観測済み読込量::空を作る();
        self.世代 = self.世代.進める();
    }

    /// 台帳が管理しているチャンクの件数。リセットが台帳を空にしたことを呼出し側が確かめられるようにする。
    pub fn 台帳登録数(&self) -> usize {
        self.台帳.登録数()
    }

    /// 読込量の観測を覚えている座標の件数。リセットで消えることを呼出し側が確かめられるようにする。
    pub fn 観測済み読込量件数(&self) -> usize {
        self.観測済み読込量.件数()
    }
}
