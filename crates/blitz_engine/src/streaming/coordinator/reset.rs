//! シーンが差し替わったときの調停のリセットを所有する。何を捨てて何を残すかの規則と、その結果を外から確かめる読み取りをここが持つ。
//! 呼び出しタイミング: レンダラーのシーン差し替えが成功した直後に1回だけ呼ぶ。差し替えは描画資源を作り直してチャンクの描画束を全部消すため、
//! 台帳をそのまま残すと台帳の常駐と実際に載っている描画束が乖離する。
//! 参照: `_doc/設計/チャンクストリーミング.md`「ホットリロードとの併用」

use super::ストリーミング調停;

use crate::streaming::chunk_ledger::チャンク台帳;

impl ストリーミング調停 {
    /// 台帳と準備済みCPUデータの保管を空にし、次のフレームから読み直させる。
    /// 実測記憶と転送量は残す。実測記憶は読み直したときの見積精度に使い、転送量は過ぎ去った事象の累計だからである。
    /// 読込器も残す。ワーカースレッドを起動し直す理由がなく、リセット前に投入した読込の完了は`完了を回収する`が破棄として片付ける。
    pub fn リセットする(&mut self) {
        self.台帳 = チャンク台帳::空を作る();
        self.準備済みシーン.clear();
    }

    /// 台帳が管理しているチャンクの件数。リセットが台帳を空にしたことを呼出し側が確かめられるようにする。
    pub fn 台帳登録数(&self) -> usize {
        self.台帳.登録数()
    }

    /// RAM実測を覚えている座標の件数。リセットで消えないことを呼出し側が確かめられるようにする。
    pub fn 実測記憶件数(&self) -> usize {
        self.実測記憶.件数()
    }
}
