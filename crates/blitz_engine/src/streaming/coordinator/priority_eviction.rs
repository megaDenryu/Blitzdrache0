//! 除外された最も近い未収容チャンクへ収容余地を作るために、それより遠い常駐チャンクを退避させる工程。
//! 受け取るのは台帳・必要集合の中心・優位の連続計数・上限・最も近い未収容候補・同じフレームで先に計画した退避一覧であり、返すのは追加で退避させる座標である。
//! 発火の条件、すなわち距離0は即時で距離1以上は連続優位の閾値、をここが持ち、どの記録を犠牲にするかの規則は台帳が持つ。
//! 参照: `_doc/設計/チャンクストリーミング.md`「近い未収容チャンクのための退避」

use crate::streaming::{
    chunk_ledger::チャンク台帳, coordinator_error::ストリーミング調停エラー, eviction_hysteresis::退避優位計数,
    memory_amount::ストリーミングメモリ量, memory_candidate::チャンク予算候補,
};
use crate::チャンク座標;

pub(super) fn 収容余地を作る(
    台帳: &チャンク台帳,
    中心: チャンク座標,
    優位計数: &mut 退避優位計数,
    上限: ストリーミングメモリ量,
    未収容の先頭: Option<チャンク予算候補>,
    計画済み: &[チャンク座標],
) -> Result<Vec<チャンク座標>, ストリーミング調停エラー> {
    let Some(候補) = 未収容の先頭 else {
        優位計数.優位なしにする();
        return Ok(Vec::new());
    };
    let 未収容距離 = u32::from(候補.要求().優先距離());
    let 計画 = 台帳.収容余地の退避を計画する(中心, 未収容距離, 候補.メモリ量(), 上限, 計画済み)?;
    if 計画.is_empty() {
        優位計数.優位なしにする();
        return Ok(Vec::new());
    }
    // 距離0はプレイヤーの足元が載っていない状態であり、猶予を置くと足元が描かれないまま留まるため、連続優位を待たずに発火させる。
    let 閾値到達 = 優位計数.優位を進める(候補.要求().座標());
    if 未収容距離 > 0 && !閾値到達 {
        return Ok(Vec::new());
    }
    優位計数.優位なしにする();
    Ok(計画)
}
