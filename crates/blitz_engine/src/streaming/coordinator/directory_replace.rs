//! 公開済みの新しいチャンク目録へ差し替える局面。触れるのは目録と、目録の内容に拘束された調停状態だけである。
//! 呼び出しタイミング: 生成台帳による公開完了を検出し、カタログと目録を読み終えた直後に1回だけ呼ぶ。

use super::ストリーミング調停;
use crate::streaming::{チャンク目録, チャンク目録差し替えエラー};

impl ストリーミング調停 {
    /// 一辺が同じ新しい目録だけを採用し、旧目録に拘束された読込・常駐状態を空へ戻す。
    /// 一辺が違う場合は何も変更せず、旧世界をそのまま使い続ける。
    pub fn チャンク目録を差し替える(
        &mut self, 新しい目録: チャンク目録
    ) -> Result<(), チャンク目録差し替えエラー> {
        let 旧一辺 = self.目録.一辺();
        let 新一辺 = 新しい目録.一辺();
        if 旧一辺 != 新一辺 {
            return Err(チャンク目録差し替えエラー::チャンク一辺変更 {
                旧: 旧一辺, 新: 新一辺
            });
        }
        self.目録 = 新しい目録;
        self.リセットする();
        Ok(())
    }
}
