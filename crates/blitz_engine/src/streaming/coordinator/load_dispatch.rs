//! 読込器への要求投入を所有する。触れるのは`読込器`と`目録`、および投入が成功した座標だけを`台帳`の読込中へ進める操作である。
//! 要求キューが満杯のときに中心優先の投入順を崩さない打ち切り規律と、「投入が成功してから台帳を進める」順序をここが持つ。
//! 受け取るのは今フレームに新しく登録した読込要求一覧、返すのは実際に投入できた座標である。
//! 参照: `_doc/設計/チャンクストリーミング.md`「フレームループへの配線」

use super::ストリーミング調停;

use crate::streaming::{
    chunk_request::チャンク要求, coordinator_error::ストリーミング調停エラー, loader::チャンク読込エラー, reset_generation::リセット世代,
};
use crate::{カタログ, チャンク座標};

impl ストリーミング調停 {
    /// `世代`は投入する読込に刻むリセット世代であり、完了の回収が同じ値かどうかで古い完了を退ける。
    pub(super) fn 読込を投入する(
        &mut self,
        読込要求一覧: &[チャンク要求],
        カタログ: &カタログ,
        世代: リセット世代,
    ) -> Result<Vec<チャンク座標>, ストリーミング調停エラー> {
        let mut 開始一覧 = Vec::new();
        for 要求 in 読込要求一覧 {
            let 座標 = 要求.座標();
            let アセット = self.目録.アセットを引く(座標).ok_or(ストリーミング調停エラー::目録解決不整合(座標))?;
            match self.読込器.読込を要求する(座標, アセット, カタログ, 世代) {
                Ok(()) => {}
                // 満杯なら次フレームで再試行する。中心優先の投入順を崩さないため、以降の要求も今フレームは投入しない。
                Err(チャンク読込エラー::要求キュー満杯) => break,
                Err(誤り) => return Err(誤り.into()),
            }
            self.台帳.読込を開始する(座標)?;
            開始一覧.push(座標);
        }
        Ok(開始一覧)
    }
}
