//! 現在使用量が上限を超えているフレームの反映と退避を担当する工程。受け取るのは中心優先の解決済み候補一覧と必要集合の中心、返すのは予算判定と集合差分である。
//! 予算をこのフレームへ適用しないのは、予算がこの状態を入力エラーとして拒み、握り潰さない限り以降のフレームでも同じ失敗を繰り返すためである。
//! 新規収容をせず、既に台帳にある座標だけを必要のまま反映してから退避する。反映は不要になった常駐を解除待ちへ進めるため、反映より先に退避すると、そのフレームで解放される分まで使用量に数えて必要な常駐を余分に消す。
//! 参照: `_doc/設計/チャンクストリーミング.md`「上限を超えたフレームの退避」

use super::priority_eviction;

use crate::streaming::{
    chunk_diff::チャンク集合差分, chunk_ledger::チャンク台帳, coordinator_error::ストリーミング調停エラー, eviction_hysteresis::退避優位計数,
    memory_budget::ストリーミング予算, memory_candidate::チャンク予算候補, memory_result::予算判定,
};
use crate::チャンク座標;

pub(super) fn 退避へ倒す(
    予算: ストリーミング予算,
    台帳: &mut チャンク台帳,
    中心: チャンク座標,
    優位計数: &mut 退避優位計数,
    解決済み一覧: Vec<チャンク予算候補>,
) -> Result<(予算判定, チャンク集合差分), ストリーミング調停エラー> {
    // このフレームは新規収容をしないため、台帳に無い候補はすべて未収容である。中心優先順の先頭が最も近い未収容チャンクになる。
    let 未収容の先頭 = 解決済み一覧.iter().copied().find(|候補| 台帳.状態を引く(候補.要求().座標()).is_none());
    let 反映集合: Vec<_> = 解決済み一覧
        .into_iter()
        .filter(|候補| 台帳.状態を引く(候補.要求().座標()).is_some())
        .collect();
    let mut 差分 = 台帳.必要集合を反映する(&反映集合)?;
    let 上限超過 = 台帳.上限超過の退避を計画する(中心, 予算.上限())?;
    // 上限超過を解く分を先に計画し、収容余地の分はその結果が残す集合へ適用する。同じ座標が二度計画へ入らないよう、先の計画を渡して除く。
    let 収容余地 = priority_eviction::収容余地を作る(台帳, 中心, 優位計数, 予算.上限(), 未収容の先頭, 上限超過.退避一覧())?;
    台帳.退避を適用する(上限超過.退避一覧())?;
    台帳.退避を適用する(&収容余地)?;
    let mut 退避一覧 = 上限超過.退避一覧().to_vec();
    退避一覧.extend_from_slice(&収容余地);
    差分.解除要求を足す(&退避一覧);
    let 判定 = 予算判定::使用量超過による退避 {
        退避一覧,
        退避後も超過: 上限超過.退避後も超過(),
    };
    Ok((判定, 差分))
}
