//! 準備済みチャンクのCPUデータ保管への投入と破棄を所有する。触れるフィールドは`準備済みシーン`と、その出入りを決める`読込器`・`台帳`である。GPU転送のための取り出しは`gpu_handoff`が所有する。
//! 注意: `準備済みシーン`が保持する座標の集合は、台帳が準備済みとしている座標の集合と常に一致させる。台帳は準備済みのRAMを保持量として数えるため、両者がずれると数えている量と実際に保持している量が食い違う。

use super::ストリーミング調停;

use crate::streaming::{chunk_diff::準備完了結果, chunk_state::チャンク状態, coordinator_error::ストリーミング調停エラー};
use crate::チャンク座標;

impl ストリーミング調停 {
    /// 台帳が準備済みから外した記録の保管を同じフレームのうちに捨てる。走査順が不定なため座標順へ整列し、報告の順序を再現可能にする。
    pub(super) fn 不要なcpuデータを捨てる(&mut self) -> Vec<チャンク座標> {
        let mut 破棄一覧: Vec<_> = self
            .準備済みシーン
            .keys()
            .copied()
            .filter(|座標| self.台帳.状態を引く(*座標) != Some(チャンク状態::準備済み))
            .collect();
        破棄一覧.sort_by_key(|座標| 座標.番号を返す());
        for 座標 in &破棄一覧 {
            self.準備済みシーン.remove(座標);
        }
        破棄一覧
    }

    /// ここで準備済みへ進めた記録と`準備済みシーン`の保管が、`gpu_handoff`の`gpu転送のためにシーンデータを取り出す`の入力になる。
    pub(super) fn 完了を回収する(
        &mut self,
        破棄一覧: &mut Vec<チャンク座標>,
    ) -> Result<Vec<チャンク座標>, ストリーミング調停エラー> {
        let mut 準備完了一覧 = Vec::new();
        while let Some(完了) = self.読込器.完了を取り出す()? {
            let 座標 = 完了.チャンク();
            let 成果 = 完了.結果()?;
            let ram実測バイト数 =
                u64::try_from(成果.読込バイト数).map_err(|_| ストリーミング調停エラー::読込バイト数超過(座標))?;
            // 必要でなくなって捨てる分もディスクを読んだ事実として数えるため、台帳への反映より先に記録する。
            self.ディスク読込を記録する(ram実測バイト数)?;
            match self.台帳.準備完了を反映する(座標, ram実測バイト数)? {
                準備完了結果::GPU転送待ち => {
                    self.準備済みシーン.insert(座標, 成果.シーン);
                    準備完了一覧.push(座標);
                }
                準備完了結果::CPUデータ破棄 => 破棄一覧.push(座標),
            }
        }
        Ok(準備完了一覧)
    }
}
