//! 運んだ量の累計への記録と参照を所有する。触れるフィールドは`転送量`だけであり、他の段は事象が起きた地点からここへ1件ずつ足す。
//! 累計を状態から導出できないため調停が保持するが、加算はここに閉じてu64超過を型付きエラーにする。

use super::ストリーミング調停;

use crate::streaming::{coordinator_error::ストリーミング調停エラー, transfer_total::ストリーミング転送量};

impl ストリーミング調停 {
    /// 起動からこのフレームまでに運んだ量の累計。
    pub fn 転送量(&self) -> ストリーミング転送量 {
        self.転送量
    }

    pub(super) fn ディスク読込を記録する(&mut self, バイト数: u64) -> Result<(), ストリーミング調停エラー> {
        self.転送量 = self.転送量.ディスク読込を足す(バイト数).ok_or(ストリーミング調停エラー::転送量超過)?;
        Ok(())
    }

    pub(super) fn gpu転送を記録する(&mut self, バイト数: u64) -> Result<(), ストリーミング調停エラー> {
        self.転送量 = self.転送量.gpu転送を足す(バイト数).ok_or(ストリーミング調停エラー::転送量超過)?;
        Ok(())
    }

    pub(super) fn gpu解除を記録する(&mut self) -> Result<(), ストリーミング調停エラー> {
        self.転送量 = self.転送量.gpu解除を足す().ok_or(ストリーミング調停エラー::転送量超過)?;
        Ok(())
    }
}
