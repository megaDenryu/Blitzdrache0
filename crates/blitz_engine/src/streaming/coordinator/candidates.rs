//! 必要集合の要求一覧を、目録でアセットIDへ、カタログで容量メタデータへ解決し、読込前の量を付けた予算候補一覧にする工程。
//! 受け取るのは中心優先の要求一覧、返すのは同じ順序を保った予算候補一覧である。呼出し側は解決の内訳を知らずに呼べる。
//! 付ける量はカタログ由来の見積であり、過去に読んで観測を覚えている座標だけは見積と観測の大きいほうへそろえる。

use crate::streaming::{
    chunk_directory::チャンク目録, chunk_request::チャンク要求, coordinator_error::ストリーミング調停エラー, memory_candidate::チャンク予算候補,
    memory_estimate::チャンクメモリ量を見積もる, observed_read_size::観測済み読込量,
};
use crate::カタログ;

/// 目録に無い座標は世界の端であって異常ではないため、候補から落として読込要求を出さない。
/// 目録が解決したアセットIDがカタログに無い場合は、世界の形とアセットの所在が食い違う不整合であるため型付きエラーにする。
pub(super) fn 目録とカタログで解決する(
    目録: &チャンク目録,
    カタログ: &カタログ,
    観測済み読込量: &観測済み読込量,
    要求一覧: &[チャンク要求],
) -> Result<Vec<チャンク予算候補>, ストリーミング調停エラー> {
    let mut 候補一覧 = Vec::with_capacity(要求一覧.len());
    for 要求 in 要求一覧 {
        let Some(アセット) = 目録.アセットを引く(要求.座標()) else {
            continue;
        };
        let 項目 = カタログ
            .項目を引く(アセット)
            .ok_or_else(|| ストリーミング調停エラー::カタログ未登録(アセット.clone()))?;
        let 見積 = チャンクメモリ量を見積もる(項目.メタデータ())?;
        let メモリ量 = 観測済み読込量.見積を補正する(要求.座標(), 見積);
        候補一覧.push(チャンク予算候補::生成する(*要求, メモリ量));
    }
    Ok(候補一覧)
}
