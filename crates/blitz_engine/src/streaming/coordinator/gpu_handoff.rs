//! 調停とGPU層のあいだのチャンク受け渡しを所有する。準備済みCPUデータの引き渡し、転送完了の反映、GPU資源解除の反映という3手続きと、そのあいだの台帳の段階順をここが持つ。呼出し側は段階列を知らずに座標を渡すだけでよい。
//! 触れるのは`準備済みシーン`からの取り出しと`台帳`のGPU側段階だけである。
//! 呼び出しタイミング: `一フレーム進める`が返った後に、そのフレームの進行が挙げた座標ごとへ1回ずつ呼ぶ。フレーム内で一括処理する`prepared_data`とは呼び出し頻度が異なる。

use super::ストリーミング調停;

use crate::streaming::{
    chunk_diff::{GPU転送完了結果, 解除報告結果},
    coordinator_error::ストリーミング調停エラー,
    ledger_error::チャンク台帳エラー,
};
use crate::{シーンデータ, チャンク座標};

impl ストリーミング調停 {
    /// 準備済みチャンクのCPUデータをGPU転送のために引き渡し、台帳を`GPU転送中`へ進める。準備済みでない座標には値なしを返す。
    /// 注意: 保管からの削除と段階の前進を同時に行う。片方だけを行うと、台帳が準備済みとして数えるRAMと実際に保持している量が食い違う。
    pub fn gpu転送のためにシーンデータを取り出す(
        &mut self,
        座標: チャンク座標,
    ) -> Result<Option<シーンデータ>, ストリーミング調停エラー> {
        let Some(シーン) = self.準備済みシーン.remove(&座標) else {
            return Ok(None);
        };
        self.台帳.gpu転送を開始する(座標)?;
        let メモリ量 = self.台帳.メモリ量を参照する(座標).ok_or(チャンク台帳エラー::未登録(座標))?;
        self.gpu転送を記録する(メモリ量.vramバイト数)?;
        Ok(Some(シーン))
    }

    /// GPU転送が済んだ座標の台帳を、フレーム反映待ちを経て常駐まで進める。
    /// 前提: 呼出し側は`一フレーム進める`が準備完了として挙げた座標を、次のフレームを進める前に報告する。必要性は`一フレーム進める`の中でしか変わらないため、この報告のあいだに不要へ変わることはない。
    pub fn gpu転送の完了を報告する(&mut self, 座標: チャンク座標) -> Result<(), ストリーミング調停エラー> {
        match self.台帳.gpu転送完了を反映する(座標)? {
            GPU転送完了結果::フレーム反映待ち => {
                self.台帳.フレーム境界で常駐化する(座標)?;
                Ok(())
            }
            GPU転送完了結果::GPU資源解除待ち => Err(ストリーミング調停エラー::転送完了時に不要化(座標)),
        }
    }

    /// GPU資源を実際に破棄し終えた座標を台帳から削除する。解除待ちでない段階の座標は段階の飛ばしとして型付きエラーになる。
    /// 前提: 呼出し側は解除の予約でなく実破棄の完了を報告する。予約の時点で報告すると、台帳が数えるVRAMが実確保より先に減り、上限の空きへ新束を収容して実VRAMが上限を超える。
    /// 台帳に無い座標の報告はエラーにしない。リセットで台帳を空にした後に、リセット前に予約した実破棄が届く正常な後始末である。
    pub fn gpu資源の解除を報告する(
        &mut self, 座標: チャンク座標
    ) -> Result<解除報告結果, ストリーミング調停エラー> {
        if self.台帳.状態を参照する(座標).is_none() {
            return Ok(解除報告結果::台帳に無かった);
        }
        self.台帳.gpu使用完了後に解除する(座標)?;
        self.gpu解除を記録する()?;
        Ok(解除報告結果::台帳から削除した)
    }
}
