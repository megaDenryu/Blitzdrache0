//! 調停が保持するリセット世代の状態を所有する。触れるのは`世代`フィールドだけであり、前進と参照の2操作を持つ。
//! `リセットする`は結果を返さないため、u64を超えた前進はここが`溢れ`として保持し、次に1フレーム進めるときへ型付きエラーとして出す。
//! 溢れたまま読込を投入すると、どの完了が最新かを判別できないままアセットの古い内容を描き続けるからである。
//! 参照: `_doc/設計/チャンクストリーミング.md`「ホットリロードとの併用」

use crate::streaming::{coordinator_error::ストリーミング調停エラー, reset_generation::リセット世代};

#[derive(Debug, Clone, Copy)]
pub(super) enum 世代状態 {
    有効(リセット世代),
    溢れ,
}

impl 世代状態 {
    pub(super) fn 最初を作る() -> Self {
        Self::有効(リセット世代::最初を作る())
    }

    /// 次の世代へ進める。一度溢れたら溢れたまま留まり、以降のフレームで必ず失敗させる。
    pub(super) fn 進める(self) -> Self {
        match self {
            Self::有効(世代) => match 世代.次を作る() {
                Some(次) => Self::有効(次),
                None => Self::溢れ,
            },
            Self::溢れ => Self::溢れ,
        }
    }

    pub(super) fn 現在(self) -> Result<リセット世代, ストリーミング調停エラー> {
        match self {
            Self::有効(世代) => Ok(世代),
            Self::溢れ => Err(ストリーミング調停エラー::リセット世代超過),
        }
    }
}
