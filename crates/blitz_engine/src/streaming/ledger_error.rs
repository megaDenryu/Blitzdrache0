//! チャンク台帳の入力重複と状態遷移違反。

use crate::チャンク座標;

use super::chunk_state::チャンク状態;

#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum チャンク台帳エラー {
    #[error("必要集合でチャンク座標 {0:?}が重複した")]
    必要座標重複(チャンク座標),
    #[error("チャンク座標 {0:?}は台帳に存在しない")]
    未登録(チャンク座標),
    #[error("チャンク座標 {座標:?}は状態{実際:?}から要求された遷移を行えない")]
    状態遷移不正 {
        座標: チャンク座標, 実際: チャンク状態
    },
    #[error("台帳のRAMまたはVRAM使用量の合計がu64の範囲を超えた")]
    使用量オーバーフロー,
}
