//! 次に犠牲にする常駐記録を1件選ぶ規則を所有する。受け取るのは台帳・必要集合の中心・残してよい最短距離・目標使用量・上限・すでに犠牲へ入れた座標であり、返すのは犠牲1件か候補なしである。
//! いつ退避を起こすかは呼出し側が決め、ここは順序と対象の可否だけを決める。触れるのは各記録の状態・座標・メモリ量に限る。
//! 参照: `_doc/設計/チャンクストリーミング.md`「メモリ予算と縮退」

use super::{usage::記録の使用量, チャンク台帳};
use crate::チャンク座標;

use crate::streaming::{chunk_state::チャンク状態, memory_amount::ストリーミングメモリ量};

/// 中心から最も遠い常駐記録を選ぶ。同距離のタイブレークは座標の永続化番号の降順とし、走査順が不定なHashMapからも同じ入力で同じ順を得る。
/// 番号は座標ごとに一意であるため、最大値を取る記録は常にちょうど1つに定まる。
/// `残す最短距離`以下の常駐は選ばない。0を渡すとプレイヤーの足元だけが残り、未収容チャンクの距離を渡すと同距離の既存常駐が新規候補より優先して残る。
pub(super) fn 次の犠牲を選ぶ(
    台帳: &チャンク台帳,
    中心: チャンク座標,
    残す最短距離: u32,
    目標: ストリーミングメモリ量,
    上限: ストリーミングメモリ量,
    犠牲済み: &[チャンク座標],
) -> Option<チャンク座標> {
    台帳
        .登録一覧
        .iter()
        .filter(|(座標, 記録)| 記録.状態 == チャンク状態::常駐 && !犠牲済み.contains(座標))
        .filter(|(座標, _)| チェビシェフ距離(**座標, 中心) > 残す最短距離)
        .filter(|(_, 記録)| 超過次元を減らせるか(目標, 上限, 記録の使用量(記録)))
        .map(|(座標, _)| *座標)
        .max_by_key(|座標| (チェビシェフ距離(*座標, 中心), 座標.番号を返す()))
}

/// 上限を超えている次元の使用量を減らせる記録だけを犠牲の対象にする。
/// 常駐記録はRAMを持たないため、RAMだけが超過しているときはここで候補が尽き、効果のない解除で描画を消さずに済む。
fn 超過次元を減らせるか(
    目標: ストリーミングメモリ量, 上限: ストリーミングメモリ量, 寄与: ストリーミングメモリ量
) -> bool {
    (目標.ramバイト数 > 上限.ramバイト数 && 寄与.ramバイト数 > 0) || (目標.vramバイト数 > 上限.vramバイト数 && 寄与.vramバイト数 > 0)
}

/// チェビシェフ距離。i32の差はi32の範囲を超えうるため、符号なしの絶対差で求める。
fn チェビシェフ距離(座標: チャンク座標, 中心: チャンク座標) -> u32 {
    座標.x().abs_diff(中心.x()).max(座標.z().abs_diff(中心.z()))
}
