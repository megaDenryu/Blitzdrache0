//! 各記録の状態と保持量から現在のRAM・VRAM使用量を導出する。使用量を保管せず毎回導出するため、状態遷移のたびに
//! 使用量も更新する義務が生まれず、片方だけ更新した状態が存在しない。触れるフィールドは各記録の状態とメモリ量だけである。
//! 参照: `_doc/設計/チャンクストリーミング.md`

use super::{チャンク台帳, チャンク記録};

use crate::streaming::{
    chunk_state::チャンク状態, ledger_error::チャンク台帳エラー, memory_amount::ストリーミングメモリ量
};

impl チャンク台帳 {
    pub fn 現在使用量を導出する(&self) -> Result<ストリーミングメモリ量, チャンク台帳エラー> {
        let mut 合計 = ストリーミングメモリ量::default();
        for 記録 in self.登録一覧.values() {
            合計 = 合計.加算する(記録の使用量(記録)).ok_or(チャンク台帳エラー::使用量オーバーフロー)?;
        }
        Ok(合計)
    }
}

/// 読込待ちはまだ何も確保していない。読込中はCPU側の見積、準備済みは読込で得た実測をRAMとして数える。
/// GPU転送中はCPUデータとGPU資源が同時に存在する。転送完了後はCPUデータを破棄するためVRAMだけを数える。
fn 記録の使用量(記録: &チャンク記録) -> ストリーミングメモリ量 {
    let 保持量 = 記録.メモリ量;
    match 記録.状態 {
        チャンク状態::読込待ち => ストリーミングメモリ量::生成する(0, 0),
        チャンク状態::読込中 | チャンク状態::準備済み => ストリーミングメモリ量::生成する(保持量.ramバイト数, 0),
        チャンク状態::GPU転送中 => 保持量,
        チャンク状態::フレーム反映待ち | チャンク状態::常駐 | チャンク状態::解除待ち => {
            ストリーミングメモリ量::生成する(0, 保持量.vramバイト数)
        }
    }
}
