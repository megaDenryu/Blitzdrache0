//! 常駐チャンクを解除待ちへ退避させる計画づくりと、その計画の適用を所有する。犠牲を1件選ぶ規則は`eviction_victim`が持ち、ここは「どこまで積めば目標へ届くか」の打ち切りだけを決める。
//! 発火の条件は2つあり、上限を超えたフレームの安全退避と、近い未収容チャンクへ余地を作る退避である。どちらも同じ犠牲選択を通る。
//! 呼び出しタイミング: 必要集合を反映したあとに呼ぶ。反映より先に呼ぶと、必要のまま残る座標が解除待ちから常駐へ復帰して退避が打ち消される。
//! 参照: `_doc/設計/チャンクストリーミング.md`「メモリ予算と縮退」

use super::{eviction_victim::次の犠牲を選ぶ, usage::記録の使用量, チャンク台帳};
use crate::チャンク座標;

use crate::streaming::{
    chunk_state::チャンク状態, eviction_result::退避結果, ledger_error::チャンク台帳エラー, memory_amount::ストリーミングメモリ量,
};

impl チャンク台帳 {
    /// 現在使用量が上限を超えているフレームの退避計画。解除が済んだとみなした見込みが上限以下へ戻るまで、中心以外の遠い常駐から積む。
    /// 解除待ちの記録は解除が報告されるまでVRAMを数え続けるため、打ち切りは台帳の現在値でなく見込み量で判定する。
    pub fn 上限超過の退避を計画する(
        &self,
        中心: チャンク座標,
        上限: ストリーミングメモリ量,
    ) -> Result<退避結果, チャンク台帳エラー> {
        let (計画, 届かなかった) = 退避を計画する(self, 中心, 0, ストリーミングメモリ量::default(), 上限, &[])?;
        Ok(退避結果::生成する(計画, 届かなかった))
    }

    /// 未収容チャンク1件を後続フレームで収容できるようにする退避計画。`未収容距離`より遠い常駐だけを選び、同距離の既存常駐は残す。
    /// 余地を作りきれないときは空の計画を返す。届かない退避は描画を消すだけで収容につながらないためである。
    pub fn 収容余地の退避を計画する(
        &self,
        中心: チャンク座標,
        未収容距離: u32,
        収容量: ストリーミングメモリ量,
        上限: ストリーミングメモリ量,
        計画済み: &[チャンク座標],
    ) -> Result<Vec<チャンク座標>, チャンク台帳エラー> {
        let (計画, 届かなかった) = 退避を計画する(self, 中心, 未収容距離, 収容量, 上限, 計画済み)?;
        Ok(if 届かなかった { Vec::new() } else { 計画 })
    }

    /// 計画した座標を常駐から解除待ちへ進める。この遷移では再要求時の復帰先を残さないため、退避したチャンクが次のフレームで常駐へ戻ることはない。
    pub fn 退避を適用する(&mut self, 計画: &[チャンク座標]) -> Result<(), チャンク台帳エラー> {
        for 座標 in 計画 {
            self.状態を変更する(*座標, チャンク状態::常駐, チャンク状態::解除待ち)?;
        }
        Ok(())
    }
}

/// 退避を決めた座標の解除が済み、`追加量`を収容し終えたとみなした使用量。差し引きでなく残る記録の合計で求めるため、桁溢れの向きを1種類に保てる。
/// 注意: すでに解除待ちの記録は数えない。解除が予約済みで復帰先も残っていないため、その分へ重ねて退避を積むと描画を余分に消す。
fn 目標使用量(
    台帳: &チャンク台帳,
    退避済み: &[チャンク座標],
    追加量: ストリーミングメモリ量,
) -> Result<ストリーミングメモリ量, チャンク台帳エラー> {
    let mut 合計 = 追加量;
    for (座標, 記録) in &台帳.登録一覧 {
        if 記録.状態 == チャンク状態::解除待ち || 退避済み.contains(座標) {
            continue;
        }
        合計 = 合計.加算する(記録の使用量(記録)).ok_or(チャンク台帳エラー::使用量オーバーフロー)?;
    }
    Ok(合計)
}

/// 目標使用量が上限以下へ戻るまで犠牲を積む。戻せないまま候補が尽きたときは、そこまでの計画と「届かなかった」を返す。
fn 退避を計画する(
    台帳: &チャンク台帳,
    中心: チャンク座標,
    残す最短距離: u32,
    追加量: ストリーミングメモリ量,
    上限: ストリーミングメモリ量,
    計画済み: &[チャンク座標],
) -> Result<(Vec<チャンク座標>, bool), チャンク台帳エラー> {
    let 開始 = 計画済み.len();
    let mut 犠牲一覧 = 計画済み.to_vec();
    let mut 目標 = 目標使用量(台帳, &犠牲一覧, 追加量)?;
    while 目標.いずれかが上限を超えるか(上限) {
        let Some(座標) = 次の犠牲を選ぶ(台帳, 中心, 残す最短距離, 目標, 上限, &犠牲一覧) else {
            break;
        };
        犠牲一覧.push(座標);
        目標 = 目標使用量(台帳, &犠牲一覧, 追加量)?;
    }
    let 届かなかった = 目標.いずれかが上限を超えるか(上限);
    Ok((犠牲一覧.split_off(開始), 届かなかった))
}
