//! 使用量が上限を超えたときに常駐チャンクを解除待ちへ退避させる操作を所有する。触れるのは各記録の状態とメモリ量だけで、
//! 進める段階は常駐から解除待ちの1つに限る。どの記録を選ぶかの規則(遠い順・中心を残す・減らせる次元だけ)をここが持つ。
//! 呼び出しタイミング: 必要集合を反映したあと、現在使用量が上限を超えているフレームでだけ呼ぶ。反映より先に呼ぶと、必要のまま残る座標が解除待ちから常駐へ復帰して退避が打ち消される。
//! 参照: `_doc/設計/チャンクストリーミング.md`「メモリ予算と縮退」

use super::{usage::記録の使用量, チャンク台帳};
use crate::チャンク座標;

use crate::streaming::{
    chunk_state::チャンク状態, eviction_result::退避結果, ledger_error::チャンク台帳エラー, memory_amount::ストリーミングメモリ量,
};

impl チャンク台帳 {
    /// 中心から最も遠い常駐チャンクから順に解除待ちへ進め、解除が済んだ後の見込み使用量が上限以下になるまで続ける。
    /// 解除待ちの記録は解除が報告されるまでVRAMを数え続けるため、打ち切りの判定は台帳の現在値でなく見込み量で行う。
    /// 中心チャンク(チェビシェフ距離0)は退避しない。プレイヤーの足元の描画を消せないためである。
    pub fn 上限超過から退避する(
        &mut self,
        中心: チャンク座標,
        上限: ストリーミングメモリ量,
    ) -> Result<退避結果, チャンク台帳エラー> {
        let mut 退避一覧 = Vec::new();
        let mut 見込み = 見込み使用量(self, &退避一覧)?;
        while 見込み.いずれかが上限を超えるか(上限) {
            let Some(座標) = 退避対象を選ぶ(self, 中心, 見込み, 上限, &退避一覧) else {
                break;
            };
            退避一覧.push(座標);
            見込み = 見込み使用量(self, &退避一覧)?;
        }
        for 座標 in &退避一覧 {
            self.状態を変更する(*座標, チャンク状態::常駐, チャンク状態::解除待ち)?;
        }
        Ok(退避結果::生成する(退避一覧, 見込み.いずれかが上限を超えるか(上限)))
    }
}

/// 退避を決めた座標の解除が済んだとみなした使用量。差し引きでなく残る記録の合計で求めるため、桁溢れの向きを1種類に保てる。
fn 見込み使用量(
    台帳: &チャンク台帳, 退避済み: &[チャンク座標]
) -> Result<ストリーミングメモリ量, チャンク台帳エラー> {
    let mut 合計 = ストリーミングメモリ量::default();
    for (座標, 記録) in &台帳.登録一覧 {
        if 退避済み.contains(座標) {
            continue;
        }
        合計 = 合計.加算する(記録の使用量(記録)).ok_or(チャンク台帳エラー::使用量オーバーフロー)?;
    }
    Ok(合計)
}

/// 中心から最も遠い常駐記録を選ぶ。同距離のタイブレークは座標の永続化番号の降順とし、走査順が不定なHashMapからも同じ入力で同じ順を得る。
/// 番号は座標ごとに一意であるため、最大値を取る記録は常にちょうど1つに定まる。
fn 退避対象を選ぶ(
    台帳: &チャンク台帳,
    中心: チャンク座標,
    見込み: ストリーミングメモリ量,
    上限: ストリーミングメモリ量,
    退避済み: &[チャンク座標],
) -> Option<チャンク座標> {
    台帳
        .登録一覧
        .iter()
        .filter(|(座標, 記録)| 記録.状態 == チャンク状態::常駐 && !退避済み.contains(座標))
        .filter(|(座標, _)| チェビシェフ距離(**座標, 中心) > 0)
        .filter(|(_, 記録)| 超過次元を減らせるか(見込み, 上限, 記録の使用量(記録)))
        .map(|(座標, _)| *座標)
        .max_by_key(|座標| (チェビシェフ距離(*座標, 中心), 座標.番号を返す()))
}

/// 上限を超えている次元の使用量を減らせる記録だけを退避の対象にする。
/// 常駐記録はRAMを持たないため、RAMだけが超過しているときはここで退避が止まり、効果のない解除で描画を消さずに済む。
fn 超過次元を減らせるか(
    見込み: ストリーミングメモリ量, 上限: ストリーミングメモリ量, 寄与: ストリーミングメモリ量
) -> bool {
    (見込み.ramバイト数 > 上限.ramバイト数 && 寄与.ramバイト数 > 0) || (見込み.vramバイト数 > 上限.vramバイト数 && 寄与.vramバイト数 > 0)
}

/// チェビシェフ距離。i32の差はi32の範囲を超えうるため、符号なしの絶対差で求める。
fn チェビシェフ距離(座標: チャンク座標, 中心: チャンク座標) -> u32 {
    座標.x().abs_diff(中心.x()).max(座標.z().abs_diff(中心.z()))
}
