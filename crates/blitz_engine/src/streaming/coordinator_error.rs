//! ストリーミング調停が1フレームを進める間に起こりうる失敗。内部の各段の型付きエラーを包み、握り潰さずに呼出し側へ伝える。

use crate::{アセットID, チャンク座標, 実行時シーン読込エラー};

use super::{
    error::チャンク格子エラー, ledger_error::チャンク台帳エラー, loader::チャンク読込エラー, memory_budget::ストリーミング予算エラー,
    memory_estimate::ストリーミング見積エラー,
};

#[derive(Debug, thiserror::Error)]
pub enum ストリーミング調停エラー {
    #[error("必要チャンク集合を計算できない: {0}")]
    格子計算失敗(#[from] チャンク格子エラー),
    #[error("チャンクの見積量を作れない: {0}")]
    見積失敗(#[from] ストリーミング見積エラー),
    #[error("ストリーミング予算を適用できない: {0}")]
    予算適用失敗(#[from] ストリーミング予算エラー),
    #[error("チャンク台帳を更新できない: {0}")]
    台帳更新失敗(#[from] チャンク台帳エラー),
    #[error("チャンク読込器を操作できない: {0}")]
    読込器操作失敗(#[from] チャンク読込エラー),
    #[error("チャンクの実行時シーンを読めない: {0}")]
    シーン読込失敗(#[from] 実行時シーン読込エラー),
    #[error("チャンク目録が解決したアセットID {0}がカタログに存在しない")]
    カタログ未登録(アセットID),
    #[error("読込要求のチャンク座標(x={}, z={})を目録で解決できない", .0.x(), .0.z())]
    目録解決不整合(チャンク座標),
    #[error("チャンク座標(x={}, z={})の読込バイト数をu64で表現できない", .0.x(), .0.z())]
    読込バイト数超過(チャンク座標),
    #[error("チャンク座標(x={}, z={})がGPU転送完了の報告時に不要へ変わっていた", .0.x(), .0.z())]
    転送完了時に不要化(チャンク座標),
    #[error("運んだ量の累計がu64の範囲を超えた")]
    転送量超過,
}
