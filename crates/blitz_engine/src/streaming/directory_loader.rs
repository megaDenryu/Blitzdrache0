//! 版付きチャンク目録ファイルを読み、検証済みのチャンク目録を返す。
//! 目録はアセットIDだけを保持しパスを持たないため、カタログ読込のような配置先からのパス解決を必要としない。

use std::path::Path;

use super::{chunk_directory::チャンク目録, directory_load_error::実行時チャンク目録読込エラー};
use crate::asset::実行時形式からチャンク目録を読む;

pub fn 実行時チャンク目録を読み込む(パス: &Path) -> Result<チャンク目録, 実行時チャンク目録読込エラー> {
    let バイト列 = std::fs::read(パス)
        .map_err(|誤り| 実行時チャンク目録読込エラー::ファイル読込失敗(format!("{}: {誤り}", パス.display())))?;
    Ok(実行時形式からチャンク目録を読む(&バイト列)?)
}
