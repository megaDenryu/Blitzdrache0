//! 近い未収容チャンクが遠い常駐チャンクより優先されるべき状態が、同じ座標について何フレーム続いたかを数える。
//! 壁時計でなく調停のフレーム数で数えるため、同じ入力列からは同じ退避列を得る。
//! 計数は候補座標ごとに持つ。犠牲になりうる常駐との対ごとに持つと、犠牲の選び直しで計数が分散して閾値へ届かなくなる。
//! 参照: `_doc/設計/チャンクストリーミング.md`「近い未収容チャンクのための退避」

use std::collections::HashMap;

use crate::チャンク座標;

/// 距離1以上の未収容チャンクのために退避を発火させるまでに求める、優位が続くフレーム数。
/// プレイヤーがチャンク境界を1フレームで往復しても発火しない余裕として4フレームを置く。
/// 検証用世界の固定経路は20フレームに1回境界をまたぐため、この値は境界を越えて留まった移動だけを退避へ通す。
const 連続優位閾値: u32 = 4;

#[derive(Debug)]
pub struct 退避優位計数 {
    連続フレーム数: HashMap<チャンク座標, u32>,
}

impl 退避優位計数 {
    pub fn 空を作る() -> Self {
        Self {
            連続フレーム数: HashMap::new(),
        }
    }

    /// 優位が続いた座標の計数を1つ進め、それ以外の座標の計数を捨てる。閾値へ達していれば真を返す。
    /// 計数は閾値との比較にしか使わないため、u32を超えた先の値は判定を変えない。飽和で止める。
    pub fn 優位を進める(&mut self, 座標: チャンク座標) -> bool {
        let 回数 = {
            let 値 = self.連続フレーム数.entry(座標).or_insert(0);
            *値 = 値.saturating_add(1);
            *値
        };
        self.連続フレーム数.retain(|保持座標, _| *保持座標 == 座標);
        回数 >= 連続優位閾値
    }

    /// 優位が消えたフレームで計数を0へ戻す。発火した直後にも呼び、次の退避まで同じ猶予を置く。
    /// 退避を予約しても解除待ちが実破棄されるまで同じ優位が続くため、戻さないと後続フレームで退避が連鎖する。
    pub fn 優位なしにする(&mut self) {
        self.連続フレーム数.clear();
    }
}
