//! 上限超過からの退避で、どの座標を解除待ちへ進めたか、退避しても超過が残ったかを表す結果。

use crate::チャンク座標;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 退避結果 {
    退避一覧: Vec<チャンク座標>,
    退避後も超過: bool,
}

impl 退避結果 {
    pub(super) fn 生成する(退避一覧: Vec<チャンク座標>, 退避後も超過: bool) -> Self {
        Self {
            退避一覧, 退避後も超過
        }
    }

    /// 退避させた順。中心から遠い順であり、同距離は座標の永続化番号の降順である。
    pub fn 退避一覧(&self) -> &[チャンク座標] {
        &self.退避一覧
    }

    /// 退避しても解除後の見込み使用量が上限以下へ戻らなかったか。中心チャンクは退避しないため、中心だけで上限を超えると真のままになる。
    pub fn 退避後も超過(&self) -> bool {
        self.退避後も超過
    }
}
