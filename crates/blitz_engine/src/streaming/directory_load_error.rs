//! 版付きチャンク目録ファイルの読込で返す型付きエラー。

use crate::asset::実行時形式のファイルの読み取りの破れ;
use crate::アセット実行時形式エラー;

#[derive(Debug, thiserror::Error)]
pub enum 実行時チャンク目録読込エラー {
    #[error("実行時チャンク目録のファイル読込に失敗した: {0}")]
    ファイル読込失敗(#[from] 実行時形式のファイルの読み取りの破れ),
    #[error("実行時チャンク目録の形式検査に失敗した: {0}")]
    形式不正(#[from] アセット実行時形式エラー),
}
