use crate::streaming_chunk_world_fixture::{世界を作る, 後始末する};
use crate::streaming_coordinator_fixture::{常駐まで進める, 起動する, 進める};
use crate::{ストリーミングメモリ量, チャンク一辺, チャンク座標, チャンク目録, チャンク目録差し替えエラー};

#[test]
fn 一辺が変わる目録を拒み旧目録を保持する() {
    let (パス一覧, カタログ, 旧目録) = 世界を作る("directory_replace_side", &[(0, 0)]);
    let mut 調停 = 起動する(旧目録, ストリーミングメモリ量::生成する(100_000, 100_000), 0);
    let 新一辺 = match チャンク一辺::生成する(256.0) {
        Ok(一辺) => 一辺,
        Err(誤り) => panic!("試験用チャンク一辺を作れなかった: {誤り}"),
    };
    let 結果 = 調停.チャンク目録を差し替える(チャンク目録::空を作る(新一辺));
    assert!(matches!(
        結果,
        Err(チャンク目録差し替えエラー::チャンク一辺変更 {
            旧,
            新
        }) if 旧.f32値() == 100.0 && 新.f32値() == 256.0
    ));
    assert_eq!(進める(&mut 調停, &カタログ, 50.0).読込開始一覧().len(), 1);
    後始末する(&パス一覧);
}

#[test]
fn 同じ一辺の別世界へ差し替えると旧状態を空にして次フレームから新座標を読む() {
    let (パス一覧, カタログ, 全目録) = 世界を作る("directory_replace_world", &[(0, 0), (1, 0)]);
    let 旧座標 = チャンク座標::生成する(0, 0);
    let 新座標 = チャンク座標::生成する(1, 0);
    let mut 旧目録 = チャンク目録::空を作る(全目録.一辺());
    let mut 新目録 = チャンク目録::空を作る(全目録.一辺());
    let Some(旧アセット) = 全目録.アセットを参照する(旧座標).cloned() else {
        panic!("旧世界の試験用アセットが無い")
    };
    let Some(新アセット) = 全目録.アセットを参照する(新座標).cloned() else {
        panic!("新世界の試験用アセットが無い")
    };
    assert!(旧目録.登録する(旧座標, 旧アセット).is_ok());
    assert!(新目録.登録する(新座標, 新アセット).is_ok());
    let mut 調停 = 起動する(旧目録, ストリーミングメモリ量::生成する(100_000, 100_000), 0);
    assert_eq!(常駐まで進める(&mut 調停, &カタログ, 50.0, 1), [旧座標]);

    assert!(調停.チャンク目録を差し替える(新目録).is_ok());
    assert_eq!(調停.台帳登録数(), 0);
    assert_eq!(調停.観測済み読込量件数(), 0);
    assert_eq!(進める(&mut 調停, &カタログ, 150.0).読込開始一覧(), [新座標]);
    後始末する(&パス一覧);
}
