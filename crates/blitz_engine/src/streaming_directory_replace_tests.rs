use crate::streaming_chunk_world_fixture::{世界を作る, 後始末する};
use crate::streaming_coordinator_fixture::{起動する, 進める};
use crate::{ストリーミングメモリ量, チャンク一辺, チャンク目録, チャンク目録差し替えエラー};

#[test]
fn 一辺が変わる目録を拒み旧目録を保持する() {
    let (パス一覧, カタログ, 旧目録) = 世界を作る("directory_replace_side", &[(0, 0)]);
    let mut 調停 = 起動する(旧目録, ストリーミングメモリ量::生成する(100_000, 100_000), 0);
    let 新一辺 = match チャンク一辺::生成する(256.0) {
        Ok(一辺) => 一辺,
        Err(誤り) => panic!("試験用チャンク一辺を作れなかった: {誤り}"),
    };
    let 結果 = 調停.チャンク目録を差し替える(チャンク目録::空を作る(新一辺));
    assert!(matches!(
        結果,
        Err(チャンク目録差し替えエラー::チャンク一辺変更 {
            旧メートル: 100.0,
            新メートル: 256.0
        })
    ));
    assert_eq!(進める(&mut 調停, &カタログ, 50.0).読込開始一覧().len(), 1);
    後始末する(&パス一覧);
}
