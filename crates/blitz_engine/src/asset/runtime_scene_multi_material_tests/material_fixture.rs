//! 検査で使う材質の材料。返すのはスロット0とスロット1に別々の材質を割り当てた材質集合と、その2つの材質である。
//! 2件でベースカラーテクスチャの有無を変えているのは、材質特徴集合が材質ごとに違う値になる並びを往復させるためである。

use crate::asset::runtime_scene_tests::原寸だけのrgba8テクスチャを作る;
use crate::asset::{マテリアルデータ, 材質スロットID, 材質スロット割当, 材質集合, 金属粗さPBRデータ};

pub(crate) fn 二材質の集合を作る() -> 材質集合 {
    let 割当一覧 = vec![
        材質スロット割当 {
            スロット: 材質スロットID::生成する(0),
            マテリアル: ベースカラー付き材質を作る(),
        },
        材質スロット割当 {
            スロット: 材質スロットID::生成する(1),
            マテリアル: テクスチャ無し材質を作る(),
        },
    ];
    match 材質集合::生成する(割当一覧) {
        Ok(値) => 値,
        Err(誤り) => panic!("検査用の二材質の集合を作れなかった: {誤り}"),
    }
}

pub(crate) fn ベースカラー付き材質を作る() -> マテリアルデータ {
    マテリアルデータ::金属粗さPBR(金属粗さPBRデータ {
        ベースカラー: Some(原寸だけのrgba8テクスチャを作る(1, 1, vec![10, 20, 30, 255])),
        金属粗さ: None,
        法線マップ: None,
        ベースカラー係数: [1.0, 0.5, 0.25, 1.0],
        金属度係数: 0.2,
        粗さ係数: 0.8,
    })
}

pub(crate) fn テクスチャ無し材質を作る() -> マテリアルデータ {
    マテリアルデータ::金属粗さPBR(金属粗さPBRデータ {
        ベースカラー: None,
        金属粗さ: None,
        法線マップ: None,
        ベースカラー係数: [0.25, 0.5, 1.0, 1.0],
        金属度係数: 0.7,
        粗さ係数: 0.3,
    })
}
