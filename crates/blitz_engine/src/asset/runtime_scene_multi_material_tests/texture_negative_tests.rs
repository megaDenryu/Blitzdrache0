//! 負の対照: 版5のテクスチャの並びのうち、格納形式の判別値と段の宣言長が壊れたバイト列を読取が拒むことを確かめる。
//! 焼く手前の値は`格納済みテクスチャ`の生成が同じ条件で拒むため、ここが見るのは外から届いたバイト列だけである。
//! 参照: `_doc/設計/アセット実行時形式.md`「シーン内容の版5」

use super::patch::読んだ失敗;
use super::位置;
use crate::asset::texture_storage::格納済みテクスチャエラー;
use crate::asset::アセット実行時形式エラー;

/// 判別値は1バイトであり、u32で書き換えると縮小段数の下位バイトも同時に壊れる。
/// 格納形式の判別は縮小段数を読む前に走るため、この検査が見るのは判別値の失敗である。
#[test]
fn 未知のテクスチャ格納形式の判別値を拒む() {
    assert_eq!(
        読んだ失敗(位置::材質0のベースカラーの格納形式, 2),
        アセット実行時形式エラー::未知のテクスチャ格納形式(2)
    );
}

#[test]
fn 段の宣言長が格納形式の算術と食い違うバイト列を拒む() {
    assert_eq!(
        読んだ失敗(位置::材質0のベースカラーの段の宣言長, 3),
        アセット実行時形式エラー::格納済みテクスチャ不正(格納済みテクスチャエラー::縮小段のバイト数不一致 {
            段番号: 0,
            期待長: 4,
            実長: 3
        })
    );
}
