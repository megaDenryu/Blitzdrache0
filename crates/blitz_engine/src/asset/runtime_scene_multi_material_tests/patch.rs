//! 焼いたバイト列の指定位置をu32で壊して読ませる工程。受け取るのは位置と値、返すのは読取が出した失敗である。
//! 負の対照が共通して使うため、壊し方と読ませ方を検査ごとに書き分けない。

use super::fixture::二材質シーンを作る;
use crate::asset::{アセット実行時形式エラー, シーンを実行時形式へ格納する, 実行時形式からシーンを読む};

pub(super) fn 読んだ失敗(位置: usize, 値: u32) -> アセット実行時形式エラー {
    複数箇所を壊して読んだ失敗(&[(位置, 値)])
}

pub(super) fn 複数箇所を壊して読んだ失敗(変更一覧: &[(usize, u32)]) -> アセット実行時形式エラー {
    match 実行時形式からシーンを読む(&壊したバイト列(変更一覧)) {
        Ok(_) => panic!("壊したバイト列が読めてしまった"),
        Err(誤り) => 誤り,
    }
}

fn 壊したバイト列(変更一覧: &[(usize, u32)]) -> Vec<u8> {
    let mut バイト列 = match シーンを実行時形式へ格納する(&二材質シーンを作る()) {
        Ok(値) => 値,
        Err(誤り) => panic!("二材質シーンを焼けなかった: {誤り}"),
    };
    for (位置, 値) in 変更一覧 {
        バイト列[*位置..位置 + 4].copy_from_slice(&値.to_le_bytes());
    }
    バイト列
}
