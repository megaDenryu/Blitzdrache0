//! 二材質シーンを版5で焼いたバイト列の中の、検査が壊す位置。共通ヘッダーの先頭から数えたバイト位置である。
//! 位置を宣言でなく積み上げで書くのは、途中の並びが変わったときに1つの定数だけが古いまま残ることを避けるためである。
//! 積み上げの結果が実際の長さと一致することは`焼いた長さが積み上げと一致する`が確かめる。

/// 共通ヘッダーの長さ。内容の先頭はこのバイト数の後ろから始まる。
const ヘッダー長: usize = 24;

/// 描画対象数のu32、描画対象IDのu64、所有チャンクのu64、列優先4x4のf32が形状の判別値に先行する。
const 形状判別値: usize = ヘッダー長 + 4 + 8 + 8 + 64;

/// 頂点数のu32は形状の判別値1バイトの後ろに来る。
const 頂点数: usize = 形状判別値 + 1;

/// 添字数のu32は、頂点数のu32と頂点4件(1件48バイト)の後ろに来る。
const 添字数: usize = 頂点数 + 4 + 4 * 48;

/// プリミティブ数のu32は、添字数のu32と添字6件(1件4バイト)の後ろに来る。
const プリミティブ数: usize = 添字数 + 4 + 6 * 4;

/// プリミティブ1が指す区間の先頭にあたる、添字一覧の4件目のu32。
pub(super) const 添字一覧の4件目: usize = 添字数 + 4 + 3 * 4;

const プリミティブ0: usize = プリミティブ数 + 4;
const プリミティブ1: usize = プリミティブ0 + 16;

pub(super) const プリミティブ1のインデックス開始: usize = プリミティブ1;
pub(super) const プリミティブ1のインデックス数: usize = プリミティブ1 + 4;
pub(super) const プリミティブ1の頂点基準: usize = プリミティブ1 + 8;
pub(super) const プリミティブ1の材質スロット: usize = プリミティブ1 + 12;

/// スキン頂点属性の有無1バイトはプリミティブ列の後ろに来る。
const メッシュのスキン頂点属性有無: usize = プリミティブ1 + 16;

const 材質数: usize = メッシュのスキン頂点属性有無 + 1;
const 材質0: usize = 材質数 + 4;

/// 材質0のベースカラーテクスチャは、スロットID4・種別4・特徴集合4の後ろに来る。
const 材質0のベースカラー: usize = 材質0 + 12;

/// テクスチャ1件は有無1・幅4・高さ4・格納形式1・縮小段数4・段の宣言長8・段のバイト列の順である。
pub(super) const 材質0のベースカラーの格納形式: usize = 材質0のベースカラー + 9;
pub(super) const 材質0のベースカラーの段の宣言長: usize = 材質0のベースカラー + 14;

/// 1x1のRGBA8を1段だけ持つテクスチャは、有無から段の画素4バイトまでで26バイトになる。
const 材質0のベースカラーの次: usize = 材質0のベースカラー + 26;

/// 材質0は材質1件の並びのうち、ベースカラーの後ろに金属粗さの有無1・法線の有無1・係数24を持って終わる。
const 材質1: usize = 材質0のベースカラーの次 + 1 + 1 + 24;

pub(super) const 材質0の特徴集合: usize = 材質0 + 8;
pub(super) const 材質1のスロット: usize = 材質1;
pub(super) const 材質1の特徴集合: usize = 材質1 + 8;

/// 材質1はテクスチャを持たないため、スロットID4・種別4・特徴集合4・テクスチャの有無1×3・係数24の合計39バイトである。
/// その後ろにシーンのスキンの有無1バイトとアニメーション数のu32が続いて内容が終わる。
pub(super) const 焼いた全長: usize = 材質1 + 39 + 1 + 4;
