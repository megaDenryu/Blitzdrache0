//! 負の対照: プリミティブの区間と材質スロットの条件を、読取と書き出しの両方が拒むことを確かめる。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「入力契約と実行時形式(scene v4)」

use super::fixture::スロット集合外を指すシーンを作る;
use super::patch::{複数箇所を壊して読んだ失敗, 読んだ失敗};
use super::位置;
use crate::asset::{アセット実行時形式エラー, シーンを実行時形式へ格納する, 材質割当エラー, 材質集合エラー};

#[test]
fn 材質集合の外を指すプリミティブを拒む() {
    assert_eq!(
        読んだ失敗(位置::プリミティブ1の材質スロット, 7),
        材質割当エラー::材質スロット未定義 { 番号: 7 }.into()
    );
}

/// アセットコンパイラはこの経路で焼くため、スロット集合の外への参照はコンパイル時の失敗になる。
#[test]
fn 材質集合の外を指すプリミティブは焼く側も拒む() {
    assert_eq!(
        シーンを実行時形式へ格納する(&スロット集合外を指すシーンを作る()),
        Err(材質割当エラー::材質スロット未定義 { 番号: 5 }.into())
    );
}

#[test]
fn 材質スロットの重複を拒む() {
    assert_eq!(
        読んだ失敗(位置::材質1のスロット, 0),
        材質割当エラー::材質集合不正(材質集合エラー::スロットID重複 { 番号: 0 }).into()
    );
}

#[test]
fn インデックス数が0のプリミティブを拒む() {
    assert_eq!(
        読んだ失敗(位置::プリミティブ1のインデックス数, 0),
        材質割当エラー::空のプリミティブ.into()
    );
}

#[test]
fn インデックス一覧をはみ出す区間を拒む() {
    assert_eq!(
        読んだ失敗(位置::プリミティブ1のインデックス開始, 4),
        材質割当エラー::区間範囲外 {
            開始: 4,
            件数: 3,
            インデックス数: 6
        }
        .into()
    );
}

#[test]
fn 頂点基準を加えて頂点数を超えるプリミティブを拒む() {
    assert_eq!(
        読んだ失敗(位置::プリミティブ1の頂点基準, 3),
        材質割当エラー::頂点範囲外 {
            頂点番号: 4, 頂点数: 4
        }
        .into()
    );
}

/// 頂点基準とインデックスの和がu32を超える組を、飽和や折り返しでなく型付きエラーで拒む。
/// 区間の先頭のインデックスを1にするのは、0のままだと和が最大値のまま収まり、範囲外の枝で先に落ちるためである。
#[test]
fn 頂点基準とインデックスの和がu32を超える組を拒む() {
    assert_eq!(
        複数箇所を壊して読んだ失敗(&[(位置::添字一覧の4件目, 1), (位置::プリミティブ1の頂点基準, u32::MAX)]),
        アセット実行時形式エラー::長さ表現不能
    );
}
