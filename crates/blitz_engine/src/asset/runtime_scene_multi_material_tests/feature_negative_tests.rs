//! 負の対照: 直列化された材質特徴集合の未知ビットと、材質データとの双方向の食い違いを読取が拒むことを確かめる。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「材質特徴集合の初期確定」

use super::patch::読んだ失敗;
use super::位置;
use crate::asset::pbr_material_data::材質特徴集合エラー;
use crate::asset::材質割当エラー;

#[test]
fn 材質特徴集合の未知ビットを拒む() {
    assert_eq!(
        読んだ失敗(位置::材質0の特徴集合, 0b1001),
        材質割当エラー::材質特徴集合不正(材質特徴集合エラー::未知のビット {
            生値: 0b1001,
            未知のビット: 0b1000
        })
        .into()
    );
}

#[test]
fn ビット有りでデータ無しの材質を拒む() {
    assert_eq!(
        読んだ失敗(位置::材質1の特徴集合, 1),
        材質割当エラー::材質特徴集合不正(材質特徴集合エラー::データと不一致 { 宣言: 1, 導出: 0 }).into()
    );
}

#[test]
fn ビット無しでデータ有りの材質を拒む() {
    assert_eq!(
        読んだ失敗(位置::材質0の特徴集合, 0),
        材質割当エラー::材質特徴集合不正(材質特徴集合エラー::データと不一致 { 宣言: 0, 導出: 1 }).into()
    );
}
