//! 材質特徴集合の導出・復元・照合の検査。期待値は実装の式を写さず、設計で確定した数値をそのまま書く。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「材質特徴集合の初期確定」

use super::features_error::材質特徴集合エラー;
use super::{材質特徴集合, 金属粗さPBRデータ};
use crate::asset::texture_data::{テクスチャデータ, 白テクスチャデータを作る};

fn 材質を作る(
    ベースカラー: Option<テクスチャデータ>,
    金属粗さ: Option<テクスチャデータ>,
    法線マップ: Option<テクスチャデータ>,
) -> 金属粗さPBRデータ {
    金属粗さPBRデータ {
        ベースカラー,
        金属粗さ,
        法線マップ,
        ベースカラー係数: [1.0, 1.0, 1.0, 1.0],
        金属度係数: 0.0,
        粗さ係数: 1.0,
    }
}

#[test]
fn テクスチャの有無から確定した3ビットを導出する() {
    let 事例一覧: [(bool, bool, bool, u32); 8] = [
        (false, false, false, 0),
        (true, false, false, 1),
        (false, true, false, 2),
        (true, true, false, 3),
        (false, false, true, 4),
        (true, false, true, 5),
        (false, true, true, 6),
        (true, true, true, 7),
    ];
    for (ベースカラー有, 金属粗さ有, 法線有, 期待) in 事例一覧 {
        let 特徴 = 材質特徴集合::テクスチャの有無から導出する(ベースカラー有, 金属粗さ有, 法線有);
        assert_eq!(特徴.生値(), 期待);
        assert_eq!(特徴.ベースカラーテクスチャ有(), ベースカラー有);
        assert_eq!(特徴.金属粗さテクスチャ有(), 金属粗さ有);
        assert_eq!(特徴.法線テクスチャ有(), 法線有);
    }
}

#[test]
fn 既知の8通りは復元できて生値が保たれる() {
    for 生値 in [0, 1, 2, 3, 4, 5, 6, 7] {
        assert_eq!(材質特徴集合::生値から復元する(生値).map(材質特徴集合::生値), Ok(生値));
    }
}

#[test]
fn 未知のビットは復元を拒む() {
    assert_eq!(
        材質特徴集合::生値から復元する(8),
        Err(材質特徴集合エラー::未知のビット {
            生値: 8, 未知のビット: 8
        })
    );
    assert_eq!(
        材質特徴集合::生値から復元する(0xFFFF_FFFF),
        Err(材質特徴集合エラー::未知のビット {
            生値: 0xFFFF_FFFF,
            未知のビット: 0xFFFF_FFF8
        })
    );
}

#[test]
fn 材質から導出した特徴集合はテクスチャの有無に一致する() {
    let 材質 = 材質を作る(Some(白テクスチャデータを作る()), None, Some(白テクスチャデータを作る()));
    assert_eq!(材質.特徴集合().生値(), 5);
    assert_eq!(材質.宣言された特徴集合と照合する(材質.特徴集合()), Ok(()));
}

#[test]
fn ビット有りでデータ無しの宣言を拒む() {
    let 材質 = 材質を作る(None, None, None);
    let 宣言 = 材質特徴集合::テクスチャの有無から導出する(true, false, false);
    assert_eq!(
        材質.宣言された特徴集合と照合する(宣言),
        Err(材質特徴集合エラー::データと不一致 { 宣言: 1, 導出: 0 })
    );
}

#[test]
fn ビット無しでデータ有りの宣言を拒む() {
    let 材質 = 材質を作る(Some(白テクスチャデータを作る()), None, None);
    let 宣言 = 材質特徴集合::テクスチャの有無から導出する(false, false, false);
    assert_eq!(
        材質.宣言された特徴集合と照合する(宣言),
        Err(材質特徴集合エラー::データと不一致 { 宣言: 0, 導出: 1 })
    );
}
