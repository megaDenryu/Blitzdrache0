//! 材質特徴集合の復元と照合が返す失敗型。読み手が取る手当てが違う3つを別の枝で表す。

#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum 材質特徴集合エラー {
    #[error("材質特徴集合{生値:#x}に未知のビット{未知のビット:#x}が立っている")]
    未知のビット { 生値: u32, 未知のビット: u32 },
    #[error("材質特徴集合{生値:#x}は既知のビットだけからなるが、対応可能な組合せの一覧に無い")]
    未対応の組合せ { 生値: u32 },
    #[error("材質特徴集合の宣言{宣言:#x}と、材質データから導出した{導出:#x}が一致しない")]
    データと不一致 { 宣言: u32, 導出: u32 },
}
