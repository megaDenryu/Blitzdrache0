//! 標準金属粗さPBRの材質特徴集合。同じシェーディングモデルの内側で、互いに直交して有無が変わる機能をビット集合で表す。
//! ビット番号を数値の定数として固定するのは、列挙の序数から導出すると枝の並べ替えで直列化の意味が変わるためである。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「材質特徴集合の初期確定」

use super::features_error::材質特徴集合エラー;

/// bit0。ベースカラーテクスチャを持つ。
const ベースカラーテクスチャ有のビット: u32 = 0b001;
/// bit1。金属粗さテクスチャを持つ。
const 金属粗さテクスチャ有のビット: u32 = 0b010;
/// bit2。法線テクスチャを持つ。
const 法線テクスチャ有のビット: u32 = 0b100;

/// 実装が意味を与えているビットの全体。bit3以降は未定義であり0でなければならない。
const 既知のビットマスク: u32 = 0b111;

/// 描けると宣言した組合せの閉じた一覧であり、材質能力の検証表の正本である。
/// 3つのビットは「テクスチャがあれば標本して係数へ掛け、無ければ係数と幾何法線だけを使う」という互いに独立な有無であるため、初期は8通りすべてに対応する。
const 対応可能な組合せ一覧: [u32; 8] = [0b000, 0b001, 0b010, 0b011, 0b100, 0b101, 0b110, 0b111];

/// 標準金属粗さPBRが持つ直交した機能の有無。直列化は固定幅u32リトルエンディアンであり、GPUの材質レコードへそのまま運べる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct 材質特徴集合(u32);

impl 材質特徴集合 {
    /// テクスチャの有無だけが特徴集合を決める。生のu32を受け取る生成関数を公開しないのは、
    /// 対応データと食い違うビットを外から作れないようにするためである。
    pub fn テクスチャの有無から導出する(ベースカラー有: bool, 金属粗さ有: bool, 法線有: bool) -> Self {
        let mut 値 = 0;
        if ベースカラー有 {
            値 |= ベースカラーテクスチャ有のビット;
        }
        if 金属粗さ有 {
            値 |= 金属粗さテクスチャ有のビット;
        }
        if 法線有 {
            値 |= 法線テクスチャ有のビット;
        }
        Self(値)
    }

    /// 直列化されたu32から復元する。未知のビットを先に拒み、既知のビットだけからなる組合せを検証表と照合する。
    /// 2つを別の失敗にするのは、形式が先へ進んだ場合と実装が組合せに追いついていない場合で、読み手が取る手当てが違うためである。
    pub fn 生値から復元する(生値: u32) -> Result<Self, 材質特徴集合エラー> {
        let 未知のビット = 生値 & !既知のビットマスク;
        if 未知のビット != 0 {
            return Err(材質特徴集合エラー::未知のビット { 生値, 未知のビット });
        }
        if !対応可能な組合せ一覧.contains(&生値) {
            return Err(材質特徴集合エラー::未対応の組合せ { 生値 });
        }
        Ok(Self(生値))
    }

    /// 直列化とGPU境界で使う固定幅の値を返す。
    pub fn 生値(self) -> u32 {
        self.0
    }

    pub fn ベースカラーテクスチャ有(self) -> bool {
        self.0 & ベースカラーテクスチャ有のビット != 0
    }

    pub fn 金属粗さテクスチャ有(self) -> bool {
        self.0 & 金属粗さテクスチャ有のビット != 0
    }

    pub fn 法線テクスチャ有(self) -> bool {
        self.0 & 法線テクスチャ有のビット != 0
    }
}
