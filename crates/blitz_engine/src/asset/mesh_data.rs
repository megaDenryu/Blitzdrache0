//! メッシュデータ: 1つのメッシュが共有して格納する頂点一覧・インデックス一覧と、それを塗り分ける非空のプリミティブ列。

use super::material_slot_id::材質スロットID;
use super::mesh_primitive::メッシュプリミティブ;
use super::skin_vertex_attribute::スキン頂点属性;
use super::vertex_attribute::メッシュ頂点属性;

/// 頂点一覧とインデックス一覧の組。
///
/// `スキン頂点属性一覧`はスキン付きメッシュのみ`Some`で、`頂点一覧`と同じ長さになる
/// (判断42)。スキン無しメッシュは`None`のままで、既存の静的シーンは無変更で通る。
///
/// `プリミティブ列`は非空でなければならない。空でないことと、各区間がインデックス一覧に収まることは
/// 実行時形式の読み書きが検査する。頂点・インデックスと同じく、この型は検証を持たない格納の器である。
#[derive(Debug, Clone, PartialEq)]
pub struct メッシュデータ {
    pub 頂点一覧: Vec<メッシュ頂点属性>,
    pub インデックス一覧: Vec<u32>,
    pub スキン頂点属性一覧: Option<Vec<スキン頂点属性>>,
    pub プリミティブ列: Vec<メッシュプリミティブ>,
}

impl メッシュデータ {
    /// 全インデックスをスロット番号0の1プリミティブで塗るメッシュを作る。
    /// 単一材質のメッシュと、プリミティブ列を持たない旧版のシーンからの変換がこの関数を通る。
    pub fn 単一プリミティブで生成する(
        頂点一覧: Vec<メッシュ頂点属性>,
        インデックス一覧: Vec<u32>,
        スキン頂点属性一覧: Option<Vec<スキン頂点属性>>,
    ) -> Self {
        let プリミティブ列 = vec![メッシュプリミティブ {
            インデックス開始: 0,
            インデックス数: インデックス一覧.len(),
            頂点基準: 0,
            材質スロット: 材質スロットID::生成する(0),
        }];
        Self {
            頂点一覧,
            インデックス一覧,
            スキン頂点属性一覧,
            プリミティブ列,
        }
    }
}
