#[test]
fn 座標が重複した内容を拒否する() {
    let 内容 = 重複内容を組み立てる();
    let Ok(バイト列) = super::実行時アセットを格納する(super::実行時アセット種別::チャンク目録, &内容) else {
        panic!("試験用内容を格納できなかった");
    };
    assert!(matches!(
        実行時形式からチャンク目録を読む(&バイト列),
        Err(アセット実行時形式エラー::チャンク目録座標重複(_))
    ));
}

/// 同じ座標の項目を2件持つ版1内容を、書き出し側を経由せずに直接組み立てる。
fn 重複内容を組み立てる() -> Vec<u8> {
    let mut 内容 = Vec::new();
    内容.extend_from_slice(&2_u32.to_le_bytes());
    for _ in 0..2 {
        内容.extend_from_slice(&チャンク座標::生成する(1, 2).番号を返す().to_le_bytes());
        内容.extend_from_slice(&4_u32.to_le_bytes());
        内容.extend_from_slice(b"same");
    }
    内容
}

fn 試験用目録() -> チャンク目録 {
    let mut 目録 = チャンク目録::空を作る();
    for (x, z) in [(-2, -1), (0, 0), (2, 2)] {
        let Ok(アセット) = アセットID::生成する(&format!("chunk_x{x}_z{z}")) else {
            panic!("試験用IDを生成できなかった");
        };
        if let Err(誤り) = 目録.登録する(チャンク座標::生成する(x, z), アセット) {
            panic!("試験用目録へ登録できなかった: {誤り}");
        }
    }
    目録
}
