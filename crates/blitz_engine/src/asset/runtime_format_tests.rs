use super::runtime_format::{
    アセット実行時形式エラー, アセット形式版, 実行時アセットを格納する, 実行時アセットを開く, 実行時アセット種別
};

#[test]
fn 同じ内容は同じバイト列になる() {
    let Ok(一回目) = 実行時アセットを格納する(実行時アセット種別::シーン, b"scene") else {
        panic!("1回目のアセット実行時形式を格納できなかった");
    };
    let Ok(二回目) = 実行時アセットを格納する(実行時アセット種別::シーン, b"scene") else {
        panic!("2回目のアセット実行時形式を格納できなかった");
    };
    assert_eq!(一回目, 二回目);
}

#[test]
fn 格納した内容を検証して開く() {
    let Ok(バイト列) = 実行時アセットを格納する(実行時アセット種別::シーン, b"scene") else {
        panic!("テスト用のアセット実行時形式を格納できなかった");
    };
    let Ok(結果) = 実行時アセットを開く(&バイト列) else {
        panic!("テスト用のアセット実行時形式を開けなかった");
    };
    assert_eq!(結果.形式版, アセット形式版::V1);
    assert_eq!(結果.種別, 実行時アセット種別::シーン);
    assert_eq!(結果.内容, b"scene");
}

#[test]
fn 壊れたヘッダーと内容長を型付きエラーにする() {
    let 短い = 実行時アセットを開く(b"BLITZ");
    assert!(matches!(短い, Err(アセット実行時形式エラー::ヘッダー不足 { .. })));

    let Ok(mut バイト列) = 実行時アセットを格納する(実行時アセット種別::シーン, b"scene") else {
        panic!("テスト用のアセット実行時形式を格納できなかった");
    };
    バイト列.pop();
    let 長さ不一致 = 実行時アセットを開く(&バイト列);
    assert!(matches!(長さ不一致, Err(アセット実行時形式エラー::内容長不一致 { .. })));
}

#[test]
fn 固定識別値と未知の番号を型付きエラーにする() {
    let Ok(正常) = 実行時アセットを格納する(実行時アセット種別::シーン, b"scene") else {
        panic!("テスト用のアセット実行時形式を格納できなかった");
    };
    let mut 識別値不正 = 正常.clone();
    識別値不正[0] = b'X';
    assert!(matches!(
        実行時アセットを開く(&識別値不正),
        Err(アセット実行時形式エラー::固定識別値不一致)
    ));

    let mut 版不正 = 正常.clone();
    版不正[8..12].copy_from_slice(&2_u32.to_le_bytes());
    assert!(matches!(実行時アセットを開く(&版不正), Err(アセット実行時形式エラー::未対応形式版(2))));

    let mut 種別不正 = 正常;
    種別不正[12..16].copy_from_slice(&4_u32.to_le_bytes());
    assert!(matches!(
        実行時アセットを開く(&種別不正),
        Err(アセット実行時形式エラー::未知のアセット種別(4))
    ));
}
