//! 静的TRS: glTFノードのバインド時ローカル姿勢(アニメーション適用前の値)。

/// 平行移動・回転(クォータニオンxyzw)・スケールの組。
///
/// アニメーションチャンネルが無い成分の既定値として使う(判断49: glTF仕様では
/// チャンネルが無いプロパティはこのバインド時静的値を使う。恒等ではない)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 静的TRS {
    pub 平行移動: [f32; 3],
    pub 回転: [f32; 4],
    pub スケール: [f32; 3],
}
