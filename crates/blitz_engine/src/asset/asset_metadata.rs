//! カタログに格納する実行時容量の見積もり情報。

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct アセットメタデータ {
    pub 頂点数: u64,
    pub インデックス数: u64,
    /// 格納形式で数えたテクスチャのバイト数であり、GPUへ載る実バイト数と一致する。
    pub テクスチャ格納バイト数: u64,
    /// インスタンス群の個体の総数。個体ごとの配置と描画用変換がRAMとVRAMを占めるため、頂点数と別に数える。
    /// インスタンス群を持たないアセットでは0である。
    pub 個体数: u64,
}
