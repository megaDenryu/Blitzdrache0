//! 版3のインスタンス群に対する往復と読取境界の検査。書き出したバイト列の既知の位置を壊し、読取が型付きエラーで拒否することを確かめる。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「インスタンス群の表現」

#![allow(clippy::unwrap_used)]

mod fixture;

use super::{
    アセット実行時形式エラー, インスタンス群, インスタンス群エラー, シーンを実行時形式へ格納する, スキン頂点属性, チャンクアンカーからの許容メートル,
    メッシュデータ, 原型, 実行時形式からシーンを読む, 描画形状,
};
use fixture::{境界を作る, 最小メッシュを作る, 植生シーンを作る};

/// 共通ヘッダーの長さ。内容の先頭はこのバイト数の後ろから始まる。
const ヘッダー長: usize = 24;

/// 内容の先頭から数えた配置件数の位置。描画対象数のu32、描画対象IDのu64、所有チャンクのu64、列優先4x4のf32、
/// 形状の判別値1バイト、原型の段数u32、最小メッシュ1つ分61バイトがこの順で先行する。
const 配置件数の位置: usize = 4 + 8 + 8 + 64 + 1 + 4 + 61;

/// 配置1件の先頭にある平行移動X成分の位置。件数のu32の直後である。
const 先頭配置のX位置: usize = 配置件数の位置 + 4;

#[test]
fn インスタンス群を持つシーンを決定的に往復する() {
    let シーン = 植生シーンを作る(3);
    let 一回目 = シーンを実行時形式へ格納する(&シーン).unwrap();
    let 二回目 = シーンを実行時形式へ格納する(&シーン).unwrap();
    assert_eq!(一回目, 二回目);
    let 読み取り = 実行時形式からシーンを読む(&一回目).unwrap();
    assert_eq!(読み取り, シーン);
    let 描画形状::インスタンス群(群) = 読み取り.先頭の描画対象().形状() else {
        panic!("インスタンス群として読めなかった");
    };
    assert_eq!(群.個体数(), 3);
    assert_eq!(群.原型().段数(), 1);
}

#[test]
fn チャンクアンカーから離れすぎた配置を拒否する() {
    let mut バイト列 = シーンを実行時形式へ格納する(&植生シーンを作る(2)).unwrap();
    let 位置 = ヘッダー長 + 先頭配置のX位置;
    バイト列[位置..位置 + 4].copy_from_slice(&(チャンクアンカーからの許容メートル + 1.0).to_le_bytes());
    assert_eq!(
        実行時形式からシーンを読む(&バイト列),
        Err(アセット実行時形式エラー::インスタンス群不正(
            インスタンス群エラー::平行移動範囲外 { 軸: "X" }
        ))
    );
}

#[test]
fn 非有限の配置を拒否する() {
    let mut バイト列 = シーンを実行時形式へ格納する(&植生シーンを作る(2)).unwrap();
    let 位置 = ヘッダー長 + 先頭配置のX位置;
    バイト列[位置..位置 + 4].copy_from_slice(&f32::NAN.to_le_bytes());
    assert_eq!(実行時形式からシーンを読む(&バイト列), Err(アセット実行時形式エラー::非有限小数));
}

#[test]
fn 個体数を宣言だけ増やしたバイト列を確保前に拒否する() {
    let mut バイト列 = シーンを実行時形式へ格納する(&植生シーンを作る(2)).unwrap();
    let 位置 = ヘッダー長 + 配置件数の位置;
    バイト列[位置..位置 + 4].copy_from_slice(&100_000_u32.to_le_bytes());
    assert!(matches!(
        実行時形式からシーンを読む(&バイト列),
        Err(アセット実行時形式エラー::件数過大 { .. })
    ));
}

#[test]
fn 配置列が空の群とスキン頂点属性を持つ原型段を拒否する() {
    assert_eq!(
        インスタンス群::生成する(原型::生成する(vec![最小メッシュを作る()]).unwrap(), Vec::new(), 境界を作る()),
        Err(インスタンス群エラー::配置なし)
    );
    let スキン付き = メッシュデータ {
        スキン頂点属性一覧: Some(vec![スキン頂点属性 {
            ジョイント: [0, 0, 0, 0],
            ウェイト: [1.0, 0.0, 0.0, 0.0],
        }]),
        ..最小メッシュを作る()
    };
    assert_eq!(
        原型::生成する(vec![スキン付き]),
        Err(インスタンス群エラー::原型段にスキン頂点属性がある { 段番号: 0 })
    );
}
