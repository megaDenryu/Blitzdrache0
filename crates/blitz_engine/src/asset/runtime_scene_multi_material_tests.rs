#[test]
fn 焼いた長さが積み上げと一致する() {
    let バイト列 = シーンを実行時形式へ格納する(&二材質シーンを作る()).unwrap();
    assert_eq!(バイト列.len(), 位置::焼いた全長);
}

#[test]
fn 二材質のシーンを決定的に往復する() {
    let シーン = 二材質シーンを作る();
    let 一回目 = シーンを実行時形式へ格納する(&シーン).unwrap();
    let 二回目 = シーンを実行時形式へ格納する(&シーン).unwrap();
    assert_eq!(一回目, 二回目);
    assert_eq!(一回目[8..12], アセット形式版::V6.番号().to_le_bytes());
    assert_eq!(実行時形式からシーンを読む(&一回目).unwrap(), シーン);
}

#[test]
fn 往復したプリミティブ列が区間と頂点基準とスロットを保つ() {
    let バイト列 = シーンを実行時形式へ格納する(&二材質シーンを作る()).unwrap();
    let 読み取り = 実行時形式からシーンを読む(&バイト列).unwrap();
    let 描画形状::通常メッシュ(メッシュ) = 読み取り.先頭の描画対象().形状() else {
        panic!("二材質シーンが通常メッシュとして読めなかった");
    };
    assert_eq!(メッシュ.プリミティブ列.len(), 2);
    assert_eq!(メッシュ.プリミティブ列[0].インデックス開始, 0);
    assert_eq!(メッシュ.プリミティブ列[0].インデックス数, 3);
    assert_eq!(メッシュ.プリミティブ列[0].頂点基準, 0);
    assert_eq!(メッシュ.プリミティブ列[0].材質スロット.番号を返す(), 0);
    assert_eq!(メッシュ.プリミティブ列[1].インデックス開始, 3);
    assert_eq!(メッシュ.プリミティブ列[1].インデックス数, 3);
    assert_eq!(メッシュ.プリミティブ列[1].頂点基準, 2);
    assert_eq!(メッシュ.プリミティブ列[1].材質スロット.番号を返す(), 1);
}

#[test]
fn 往復した材質集合がスロットごとの材質と特徴集合を保つ() {
    let バイト列 = シーンを実行時形式へ格納する(&二材質シーンを作る()).unwrap();
    let 読み取り = 実行時形式からシーンを読む(&バイト列).unwrap();
    let 材質集合 = 読み取り.先頭の描画対象().材質集合();
    assert_eq!(材質集合.件数(), 2);
    assert_eq!(材質集合.割当一覧()[0].スロット.番号を返す(), 0);
    assert_eq!(材質集合.割当一覧()[1].スロット.番号を返す(), 1);
    assert_eq!(材質集合.材質を参照する(材質スロットID::生成する(0)), Some(&ベースカラー付き材質を作る()));
    assert_eq!(材質集合.材質を参照する(材質スロットID::生成する(1)), Some(&テクスチャ無し材質を作る()));
    assert_eq!(材質集合.材質を参照する(材質スロットID::生成する(2)), None);
    let crate::asset::マテリアルデータ::金属粗さPBR(スロット0) = &材質集合.割当一覧()[0].マテリアル else {
        panic!("スロット0が金属粗さPBRの枝で読めなかった");
    };
    let crate::asset::マテリアルデータ::金属粗さPBR(スロット1) = &材質集合.割当一覧()[1].マテリアル else {
        panic!("スロット1が金属粗さPBRの枝で読めなかった");
    };
    assert_eq!(スロット0.特徴集合().生値(), 1);
    assert_eq!(スロット1.特徴集合().生値(), 0);
}
