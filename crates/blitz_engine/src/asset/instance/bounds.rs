//! インスタンス群の保守的な境界。群全体を覆う包囲領域と、原型1体を覆う境界球の組である。
//! 2段階の可視判定が粗い判定に包囲領域を、細かい判定に境界球を使うため、2つを1つの型が組で持つ。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」

use super::bounding_box::軸平行包囲領域;
use super::bounding_sphere::境界球;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 群境界 {
    群の包囲領域: 軸平行包囲領域,
    原型の境界球: 境界球,
}

impl 群境界 {
    pub fn 生成する(群の包囲領域: 軸平行包囲領域, 原型の境界球: 境界球) -> Self {
        Self {
            群の包囲領域, 原型の境界球
        }
    }

    pub fn 群の包囲領域(&self) -> 軸平行包囲領域 {
        self.群の包囲領域
    }

    pub fn 原型の境界球(&self) -> 境界球 {
        self.原型の境界球
    }
}
