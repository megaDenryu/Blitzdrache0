//! インスタンス群の個体1件の配置。チャンクの基準原点からの相対のf32のTRSで表す。
//! 個体ごとのf64大域位置を持たないのは、所有チャンク内の配置が高々チャンク一辺の距離に収まり、
//! f64にしても精度が増えずRAMと転送量だけが増えるためである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「座標系」

use blitz_math::{クォータニオン, メートル, ローカル, 位置, 変換};

use super::error::{インスタンス群エラー, 軸名一覧};

/// 個体の平行移動がチャンクの基準原点から離れてよい上限。
/// 一辺100メートルのチャンクの内側という設計前提に対して十分な余裕を取りつつ、
/// この距離でもf32の刻みが0.0001メートルより細かく保たれる範囲を上限にする。
pub const チャンクの基準原点からの許容メートル: f32 = 1024.0;

/// 回転の長さが1からずれてよい幅。コンパイラが焼いたf32の丸めを受け入れ、明らかに壊れた値だけを拒む。
const 回転ノルム許容差: f32 = 1.0e-3;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 個体配置 {
    平行移動: [f32; 3],
    回転: [f32; 4],
    スケール: [f32; 3],
}

impl 個体配置 {
    /// 有限値・チャンクの基準原点からの範囲・変換の可逆性を検査してから受け入れる。
    /// 無言の丸めも既定値の適用もせず、破れはすべて型付きエラーにする。
    pub fn 生成する(平行移動: [f32; 3], 回転: [f32; 4], スケール: [f32; 3]) -> Result<Self, インスタンス群エラー> {
        有限を検査する(&平行移動, "平行移動")?;
        有限を検査する(&回転, "回転")?;
        有限を検査する(&スケール, "スケール")?;
        for (軸, 値) in 軸名一覧.into_iter().zip(平行移動) {
            if 値.abs() > チャンクの基準原点からの許容メートル {
                return Err(インスタンス群エラー::平行移動範囲外 { 軸 });
            }
        }
        let ノルム二乗 = 回転.iter().map(|値| 値 * 値).sum::<f32>();
        if (ノルム二乗.sqrt() - 1.0).abs() > 回転ノルム許容差 {
            return Err(インスタンス群エラー::回転を正規化できない);
        }
        for (軸, 値) in 軸名一覧.into_iter().zip(スケール) {
            if 値.abs() <= f32::EPSILON {
                return Err(インスタンス群エラー::スケール非可逆 { 軸 });
            }
        }
        Ok(Self {
            平行移動, 回転, スケール
        })
    }

    pub fn 平行移動(&self) -> [f32; 3] {
        self.平行移動
    }

    pub fn 回転(&self) -> [f32; 4] {
        self.回転
    }

    pub fn スケール(&self) -> [f32; 3] {
        self.スケール
    }

    /// 原型のローカル空間から群のローカル空間への変換。描画側は外側の描画対象の変換とこれを合成して個体1件の配置を得る。
    /// 生成時に回転の長さが1であることを確かめてあるため、この変換は必ず作れる。作れないのは不変条件が破れた場合だけである。
    pub fn 変換を作る(&self) -> 変換<ローカル, ローカル> {
        let 回転 = match クォータニオン::生成する(self.回転[0], self.回転[1], self.回転[2], self.回転[3]) {
            Ok(値) => 値,
            Err(_) => panic!("個体配置の回転が正規化済みであるという不変条件に違反した"),
        };
        let 平行移動 = 位置::生成する(
            メートル::生成する(self.平行移動[0]),
            メートル::生成する(self.平行移動[1]),
            メートル::生成する(self.平行移動[2]),
        );
        変換::trsから生成する(平行移動, 回転, self.スケール)
    }
}

fn 有限を検査する(値一覧: &[f32], 成分: &'static str) -> Result<(), インスタンス群エラー> {
    if 値一覧.iter().all(|値| 値.is_finite()) {
        Ok(())
    } else {
        Err(インスタンス群エラー::非有限成分 { 成分 })
    }
}
