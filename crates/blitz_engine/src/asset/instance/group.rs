//! 1つの原型を非空の配置列で多数描く描画形状。原型・配置列・保守的な境界の3つを組で持つ。
//! 原型を別アセットIDへの参照ではなく群が所有するのは、現行のシーン形式がメッシュとマテリアルを内包しており、
//! アセット間参照の解決・寿命・ホットリロードの契約が存在しないためである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「インスタンス群の表現」

use super::archetype::原型;
use super::bounds::群境界;
use super::coverage;
use super::error::インスタンス群エラー;
use super::placement::個体配置;

#[derive(Debug, Clone, PartialEq)]
pub struct インスタンス群 {
    原型: 原型,
    配置一覧: Vec<個体配置>,
    境界: 群境界,
}

impl インスタンス群 {
    /// 配置列が空の群は描くものが無いのに描画資源だけを確保するため、生成の時点で拒否する。
    /// 境界が中身を覆うことも同じ地点で確かめる。境界は可視判定が消費するため、覆っていない境界を受け入れると
    /// 見えている個体を不可視に落とす欠陥になり、しかも壊れているのは判定でなく読み込んだデータの側になる。
    pub fn 生成する(原型: 原型, 配置一覧: Vec<個体配置>, 境界: 群境界) -> Result<Self, インスタンス群エラー> {
        if 配置一覧.is_empty() {
            return Err(インスタンス群エラー::配置なし);
        }
        coverage::被覆を検査する(&原型, &配置一覧, 境界)?;
        Ok(Self {
            原型, 配置一覧, 境界
        })
    }

    pub fn 原型(&self) -> &原型 {
        &self.原型
    }

    pub fn 配置一覧(&self) -> &[個体配置] {
        &self.配置一覧
    }

    pub fn 個体数(&self) -> usize {
        self.配置一覧.len()
    }

    pub fn 境界(&self) -> 群境界 {
        self.境界
    }
}
