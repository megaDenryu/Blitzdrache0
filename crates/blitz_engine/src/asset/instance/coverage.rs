//! 群の境界が中身を本当に覆っているかを確かめる工程。受け取るのは原型と配置列と境界、返すのは合否である。
//! 原型・配置・境界の各生成関数は自分1つの値の形(有限であること・半径が正であること・最小が最大以下であること)しか見られず、
//! 「球が頂点を覆う」「包囲領域が個体を覆う」という3者にまたがる関係はどこにも属さないため、この工程が担う。
//! 覆っていない境界は可視判定が見えている個体を不可視に落とすことに直結するため、生成の時点で拒む。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「可視判定」

use blitz_math::{メートル, ローカル, 位置};

use super::archetype::原型;
use super::bounds::群境界;
use super::error::{インスタンス群エラー, 軸名一覧};
use super::placement::個体配置;

/// 被覆判定が受け入れる相対誤差。コンパイラが焼いた境界をf32で読み直したときの末尾ビットのずれを拒まないための幅である。
/// 半径の加算や最大絶対スケールの乗算を落とした境界は、この幅では通らない。
const 被覆許容比率: f32 = 1.0e-5;

pub(super) fn 被覆を検査する(原型: &原型, 配置一覧: &[個体配置], 境界: 群境界) -> Result<(), インスタンス群エラー> {
    原型を球が覆うことを検査する(原型, 境界)?;
    個体を包囲領域が覆うことを検査する(配置一覧, 境界)
}

/// 原型の境界球が全メッシュLOD段の全頂点を覆う。どの段を描いても球からはみ出さないことがこの条件である。
fn 原型を球が覆うことを検査する(原型: &原型, 境界: 群境界) -> Result<(), インスタンス群エラー> {
    let 球 = 境界.原型の境界球();
    let 上限 = 球.半径() * (1.0 + 被覆許容比率);
    for 段 in 原型.段一覧() {
        for 頂点 in &段.頂点一覧 {
            if 中心からの距離(頂点.位置, 球.中心()) > 上限 {
                return Err(インスタンス群エラー::境界球が原型を覆わない);
            }
        }
    }
    Ok(())
}

/// 群の包囲領域が、原型の境界球を各配置で写した個体の球をすべて覆う。半径には配置の最大絶対スケールを掛ける。
/// 前提: 配置はTRSでありせん断を含まない(`placement`が回転をクォータニオンで持つ)ため、最大絶対スケールが半径の上界になる。
/// 判定時の個体境界球は外側の描画対象変換まで合成するため別の上界を使う(参照: `crates/blitz_engine/src/visibility/instance_sphere.rs`)。
fn 個体を包囲領域が覆うことを検査する(
    配置一覧: &[個体配置], 境界: 群境界
) -> Result<(), インスタンス群エラー> {
    let 球 = 境界.原型の境界球();
    let (最小, 最大) = (境界.群の包囲領域().最小(), 境界.群の包囲領域().最大());
    for 配置 in 配置一覧 {
        let 座標 = 配置で写した中心(配置, 球.中心());
        let 広がり = 球.半径() * 配置.スケール().into_iter().map(f32::abs).fold(0.0_f32, f32::max);
        for (軸番号, 軸) in 軸名一覧.into_iter().enumerate() {
            let 許容 = (座標[軸番号].abs() + 広がり) * 被覆許容比率;
            if 座標[軸番号] - 広がり < 最小[軸番号] - 許容 || 座標[軸番号] + 広がり > 最大[軸番号] + 許容 {
                return Err(インスタンス群エラー::包囲領域が個体を覆わない { 軸 });
            }
        }
    }
    Ok(())
}

fn 配置で写した中心(配置: &個体配置, 中心: [f32; 3]) -> [f32; 3] {
    let 写した点 = 配置.変換を作る().適用する(局所位置(中心));
    [写した点.x().値(), 写した点.y().値(), 写した点.z().値()]
}

fn 局所位置(成分: [f32; 3]) -> 位置<ローカル> {
    位置::生成する(メートル::生成する(成分[0]), メートル::生成する(成分[1]), メートル::生成する(成分[2]))
}

fn 中心からの距離(点: [f32; 3], 中心: [f32; 3]) -> f32 {
    let 差 = [0, 1, 2].map(|軸| 点[軸] - 中心[軸]);
    (差[0] * 差[0] + 差[1] * 差[1] + 差[2] * 差[2]).sqrt()
}
