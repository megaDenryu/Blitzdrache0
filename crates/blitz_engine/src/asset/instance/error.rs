//! インスタンス群を構成する値が満たすべき条件を破ったときの失敗。
//! 配置・境界・原型の3つが同じ群の不変条件を分担するため、失敗も1つの型へ集める。
//!
//! 注意: この型はアセット実行時形式エラーへ合流するため、そちらと同じく`Eq`を導出できる形に保つ。
//! 破れた成分は値ではなく軸の名前で示す。

use super::placement::チャンクアンカーからの許容メートル;

/// インスタンス群の生成が拒否する理由。
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum インスタンス群エラー {
    #[error("個体配置の{成分}に有限でない値が含まれる")]
    非有限成分 { 成分: &'static str },
    #[error(
        "個体配置の平行移動の{軸}成分がチャンクアンカーからの許容範囲{}メートルを超えた",
        チャンクアンカーからの許容メートル
    )]
    平行移動範囲外 { 軸: &'static str },
    #[error("個体配置の回転クォータニオンを正規化できない")]
    回転を正規化できない,
    #[error("個体配置のスケールの{軸}成分が0に近く、変換が可逆でない")]
    スケール非可逆 { 軸: &'static str },
    #[error("インスタンス群の配置列が空である")]
    配置なし,
    #[error("原型のメッシュLOD列が空である")]
    原型段なし,
    #[error("原型のメッシュLOD段数{段数}が段番号の上限を超えた")]
    原型段数過大 { 段数: usize },
    #[error("原型の段{段番号}にスキン頂点属性が含まれている")]
    原型段にスキン頂点属性がある { 段番号: usize },
    #[error("包囲領域の{軸}成分で最小が最大を上回っている")]
    包囲領域の順序違反 { 軸: &'static str },
    #[error("境界球の半径が正の有限値でない")]
    境界球半径不正,
    #[error("原型の境界球がメッシュLOD段の頂点を覆っていない")]
    境界球が原型を覆わない,
    #[error("群の包囲領域が配置後の個体の境界球を{軸}方向で覆っていない")]
    包囲領域が個体を覆わない { 軸: &'static str },
}

/// 3成分の値のうちどれが破れたかを示す名前。エラーが値を持てないため位置で示す。
pub(super) const 軸名一覧: [&str; 3] = ["X", "Y", "Z"];
