//! インスタンス群の原型。段番号順に並んだ非空のメッシュLOD列であり、先頭が最詳細である。
//! マテリアルを持たないのは、群の全個体が共有するマテリアルを外側の描画対象データが持つためである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「インスタンス群の表現」

use super::error::インスタンス群エラー;
use crate::asset::mesh_data::メッシュデータ;

#[derive(Debug, Clone, PartialEq)]
pub struct 原型 {
    段一覧: Vec<メッシュデータ>,
}

impl 原型 {
    /// 個体はスキニングの対象にしないため、スキン頂点属性を持つ段を受け入れない。
    /// この境界で拒まないと、外部から与えられたバイト列の属性が誰にも読まれないまま無言で捨てられる。
    pub fn 生成する(段一覧: Vec<メッシュデータ>) -> Result<Self, インスタンス群エラー> {
        if 段一覧.is_empty() {
            return Err(インスタンス群エラー::原型段なし);
        }
        for (段番号, 段) in 段一覧.iter().enumerate() {
            if 段.スキン頂点属性一覧.is_some() {
                return Err(インスタンス群エラー::原型段にスキン頂点属性がある { 段番号 });
            }
        }
        Ok(Self { 段一覧 })
    }

    pub fn 段一覧(&self) -> &[メッシュデータ] {
        &self.段一覧
    }

    pub fn 段数(&self) -> usize {
        self.段一覧.len()
    }

    pub fn 最詳細メッシュ(&self) -> &メッシュデータ {
        match self.段一覧.first() {
            Some(メッシュ) => メッシュ,
            None => panic!("原型は1段以上を持つ不変条件に違反した"),
        }
    }
}
