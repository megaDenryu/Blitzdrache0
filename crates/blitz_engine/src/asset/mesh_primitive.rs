//! メッシュプリミティブ: 1つのメッシュの中で単一の材質を塗る連続した描画範囲。
//! 頂点とインデックスはメッシュが共有して格納し、プリミティブはその中の区間と材質スロットIDだけを持つ。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「入力契約と実行時形式(scene v4)」

use super::material_slot_id::材質スロットID;

/// インデックス区間・頂点基準・材質スロットIDの組。
///
/// 開始と数がusizeでありながら頂点基準がu32なのは、前2つがホスト側のインデックス一覧の添字と長さであるのに対し、
/// 頂点基準はインデックスの値へ加える頂点番号であり、インデックス一覧の要素と同じ型だからである。
/// 区間がメッシュに収まるかと、材質スロットIDが材質集合に実在するかは、実行時形式の読み書きが検査する。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct メッシュプリミティブ {
    pub インデックス開始: usize,
    pub インデックス数: usize,
    pub 頂点基準: u32,
    pub 材質スロット: 材質スロットID,
}
