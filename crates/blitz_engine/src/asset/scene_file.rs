//! カタログが指す実行時シーンのファイル1本を指す型。安定IDから作り、読むとシーンデータになる。
//!
//! カタログとIDを毎回持ち回らずこの型を作るのは、読み込みを要求してから実際に読むまでに間が空く経路
//! (ストリーミングのワーカーへ投げる読込ジョブ)があり、その間はどのファイルを読むかだけが決まっているためである。

use super::catalog::カタログ;
use super::id::アセットID;
use super::runtime_file::実行時形式のファイル;
use super::runtime_format::実行時形式からシーンを読む;
use super::runtime_load_error::実行時シーン読込エラー;
use super::scene_data::シーンデータ;

#[repr(transparent)]
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 実行時シーンのファイル(実行時形式のファイル);

impl 実行時シーンのファイル {
    /// カタログが安定IDへ対応付けたファイル。登録が無ければ値なしを返す。
    ///
    /// 登録の不在をここで失敗にしないのは、不在が何を意味するかを呼び出し側の語彙が決めるためである。
    /// 起動時とホットリロードは`実行時シーン読込エラー`の未登録として、ストリーミングは`チャンク読込エラー`の
    /// 未登録として、それぞれ自分の語彙で言う。
    pub fn カタログの安定idから作る(カタログ: &カタログ, id: &アセットID) -> Option<Self> {
        カタログ
            .パスを参照する(id)
            .map(|パス| Self(実行時形式のファイル::パスから作る(パス.to_path_buf())))
    }

    pub fn 読み込む(&self) -> Result<シーンデータ, 実行時シーン読込エラー> {
        self.読み込んで読み込んだバイト数も返す().map(|(シーン, _)| シーン)
    }

    /// 読み込みと同時に、読んだバイト数を返す。ストリーミングの計器が1チャンクあたりの読込量を数える。
    pub(crate) fn 読み込んで読み込んだバイト数も返す(
        &self,
    ) -> Result<(シーンデータ, usize), 実行時シーン読込エラー> {
        let バイト列 = self.0.バイト列を読む()?;
        let 読込バイト数 = バイト列.len();
        let mut シーン = 実行時形式からシーンを読む(&バイト列)?;
        シーン.参照ファイル一覧.push(self.0.パスの写しを作る());
        Ok((シーン, 読込バイト数))
    }
}
