//! 版1の地表層テクスチャ集を共通ヘッダーへ格納し、検証して復元する。
//! 並びの中身は`read`と`write`が持つ。
//! 参照: `_doc/設計/アセット実行時形式.md`「地表層テクスチャ集内容の版1」

mod read;
mod write;

use super::surface_layer_texture_set_error::地表層テクスチャ集実行時形式エラー;
use super::{
    アセット実行時形式エラー, アセット形式版, 実行時アセットを格納する, 実行時アセットを開く, 実行時アセット種別
};
use crate::surface_layer_textures::地表層テクスチャ集;

pub fn 地表層テクスチャ集を実行時形式へ格納する(
    テクスチャ集: &地表層テクスチャ集,
) -> Result<Vec<u8>, 地表層テクスチャ集実行時形式エラー> {
    let 内容 = write::地表層テクスチャ集内容を書く(テクスチャ集)?;
    Ok(実行時アセットを格納する(
        アセット形式版::V1,
        実行時アセット種別::地表層テクスチャ集,
        &内容,
    )?)
}

pub fn 実行時形式から地表層テクスチャ集を読む(
    バイト列: &[u8],
) -> Result<地表層テクスチャ集, 地表層テクスチャ集実行時形式エラー> {
    let アセット = 実行時アセットを開く(バイト列)?;
    match アセット.種別 {
        実行時アセット種別::地表層テクスチャ集 => match アセット.形式版 {
            アセット形式版::V1 => read::地表層テクスチャ集内容を読む(アセット.内容),
            版 @ (アセット形式版::V2 | アセット形式版::V3 | アセット形式版::V4 | アセット形式版::V5 | アセット形式版::V6 | アセット形式版::V7) => {
                Err(アセット実行時形式エラー::未対応形式版(版.番号()).into())
            }
        },
        種別 @ (実行時アセット種別::シーン | 実行時アセット種別::カタログ | 実行時アセット種別::チャンク目録 | 実行時アセット種別::高さ場) => {
            Err(アセット実行時形式エラー::アセット種別不一致 {
                期待: 実行時アセット種別::地表層テクスチャ集.番号(),
                実際: 種別.番号(),
            }
            .into())
        }
    }
}
