//! 高さ場の実行時形式の読み書きで返す型付きエラー。共通ヘッダーと境界検査の失敗、高さ場そのものの検証の失敗の2つを畳む。
//!
//! 高さ場の変種を`アセット実行時形式エラー`へ足さないのは、あの型がすでに規約の1ファイル100行の上限に達しており、
//! アセット種別を1つ足すたびに膨らむ形にすると、シーンの検査とカタログの検査と高さ場の検査が1つの語彙へ混ざるためである。
//! 種別ごとの検証はこの型のように種別ごとの語彙へ置き、共通ヘッダーの失敗を枝として畳み込む。

use super::アセット実行時形式エラー;
use crate::height_field::高さ場エラー;

#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum 高さ場実行時形式エラー {
    #[error(transparent)]
    共通形式の失敗(#[from] アセット実行時形式エラー),
    #[error(transparent)]
    高さ場の内容の失敗(#[from] 高さ場エラー),
}
