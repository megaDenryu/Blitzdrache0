//! 版1のカタログを共通ヘッダーへ格納し、検証して復元する。

mod read;
mod write;

use super::{
    アセット実行時形式エラー, アセット形式版, 実行時アセットを格納する, 実行時アセットを開く, 実行時アセット種別
};
use crate::asset::catalog::カタログ;

pub fn カタログを実行時形式へ格納する(カタログ: &カタログ) -> Result<Vec<u8>, アセット実行時形式エラー> {
    let 内容 = write::内容を書く(カタログ)?;
    実行時アセットを格納する(アセット形式版::V1, 実行時アセット種別::カタログ, &内容)
}

pub fn 実行時形式からカタログを読む(バイト列: &[u8]) -> Result<カタログ, アセット実行時形式エラー> {
    let アセット = 実行時アセットを開く(バイト列)?;
    match アセット.種別 {
        実行時アセット種別::カタログ => match アセット.形式版 {
            アセット形式版::V1 => read::内容を読む(アセット.内容),
            アセット形式版::V2 => Err(アセット実行時形式エラー::未対応形式版(アセット形式版::V2.番号())),
        },
        種別 @ (実行時アセット種別::シーン | 実行時アセット種別::チャンク目録) => {
            Err(アセット実行時形式エラー::アセット種別不一致 {
                期待: 実行時アセット種別::カタログ.番号(),
                実際: 種別.番号(),
            })
        }
    }
}
