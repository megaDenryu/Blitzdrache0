//! 地表層テクスチャ集を版1内容へ決定的に書く。並びはタイルの件数・タイルごとの材質名とベースカラー・層ごとの索引の順である。
//! タイルの並びはテクスチャ集の保持順をそのまま使うため、同じテクスチャ集からは常に同じバイト列を得る。
//!
//! テクスチャの並びをシーンの版5と同じ工程で書くのは、格納形式と縮小段の列の並びを2箇所で決めないためである。

use super::super::scene::bytes::書込先;
use super::super::scene::write_element::版5のテクスチャを書く;
use super::super::アセット実行時形式エラー;
use crate::surface_layer_textures::地表層テクスチャ集;

pub(super) fn 地表層テクスチャ集内容を書く(
    テクスチャ集: &地表層テクスチャ集
) -> Result<Vec<u8>, アセット実行時形式エラー> {
    let mut 出力 = 書込先::新規();
    出力.件数(テクスチャ集.材質ごとのタイル().len())?;
    for タイル in テクスチャ集.材質ごとのタイル() {
        let 材質名 = タイル.材質名().綴り().as_bytes();
        出力.件数(材質名.len())?;
        出力.バイト列(材質名);
        版5のテクスチャを書く(&mut 出力, Some(タイル.ベースカラー()))?;
    }
    for 索引 in テクスチャ集.層ごとの材質索引().層ごとの索引() {
        出力.u32(索引);
    }
    Ok(出力.完了する())
}
