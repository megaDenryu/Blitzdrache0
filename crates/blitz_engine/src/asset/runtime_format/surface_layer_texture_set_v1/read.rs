//! 版1の地表層テクスチャ集内容を境界検査して復元する。タイルの件数と材質名の長さは、確保の前に
//! 残りバイト数と突き合わせる。
//!
//! テクスチャを持たないタイルを型付きエラーで拒むのは、地表の層がベースカラーの無い状態で描けないためである。

use super::super::scene::bytes::読取位置;
use super::super::scene::read_element::版5のテクスチャを読む;
use super::super::surface_layer_texture_set_error::地表層テクスチャ集実行時形式エラー;
use crate::surface_layer_textures::{地表層ごとの材質索引, 地表層のタイル, 地表層の数, 地表層テクスチャ集};

/// タイル1件の最小バイト数。材質名の長さのu32と、テクスチャの有無の判別値1バイトの合計である。
const タイル最小長: usize = 5;

/// 材質名1バイトの最小バイト数。長さの単位そのものであるため1である。
const 材質名の一文字の最小長: usize = 1;

pub(super) fn 地表層テクスチャ集内容を読む(
    内容: &[u8],
) -> Result<地表層テクスチャ集, 地表層テクスチャ集実行時形式エラー> {
    let mut 入力 = 読取位置::新規(内容);
    let タイル件数 = 入力.件数(タイル最小長)?;
    let mut 材質ごとのタイル = Vec::with_capacity(タイル件数);
    for _ in 0..タイル件数 {
        材質ごとのタイル.push(タイルを1件読む(&mut 入力)?);
    }
    let mut 層ごとの索引 = [0_u32; 地表層の数];
    for 索引 in &mut 層ごとの索引 {
        *索引 = 入力.u32()?;
    }
    入力.完了を検査する()?;
    let 層ごとの材質索引 =
        地表層ごとの材質索引::件数の内側であることを確かめて生成する(層ごとの索引, 材質ごとのタイル.len())?;
    Ok(地表層テクスチャ集::生成する(材質ごとのタイル, 層ごとの材質索引)?)
}

fn タイルを1件読む(入力: &mut 読取位置<'_>) -> Result<地表層のタイル, 地表層テクスチャ集実行時形式エラー> {
    let 材質名の長さ = 入力.件数(材質名の一文字の最小長)?;
    let 材質名 = String::from_utf8(入力.バイト列(材質名の長さ)?.to_vec())
        .map_err(|_| 地表層テクスチャ集実行時形式エラー::材質名が文字列として読めない)?;
    let ベースカラー =
        版5のテクスチャを読む(入力)?.ok_or_else(|| 地表層テクスチャ集実行時形式エラー::タイルにベースカラーが無い {
            材質名: 材質名.clone(),
        })?;
    Ok(地表層のタイル::生成する(材質名, ベースカラー)?)
}
