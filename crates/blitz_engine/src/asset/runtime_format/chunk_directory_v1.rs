//! 版1のチャンク目録を共通ヘッダーへ格納し、検証して復元する。

mod read;
mod write;

use super::{
    アセット実行時形式エラー, 実行時アセットを格納する, 実行時アセットを開く, 実行時アセット種別
};
use crate::streaming::チャンク目録;

pub fn チャンク目録を実行時形式へ格納する(目録: &チャンク目録) -> Result<Vec<u8>, アセット実行時形式エラー> {
    let 内容 = write::内容を書く(目録)?;
    実行時アセットを格納する(実行時アセット種別::チャンク目録, &内容)
}

pub fn 実行時形式からチャンク目録を読む(バイト列: &[u8]) -> Result<チャンク目録, アセット実行時形式エラー> {
    let アセット = 実行時アセットを開く(バイト列)?;
    match アセット.種別 {
        実行時アセット種別::チャンク目録 => read::内容を読む(アセット.内容),
        種別 @ (実行時アセット種別::シーン | 実行時アセット種別::カタログ) => {
            Err(アセット実行時形式エラー::アセット種別不一致 {
                期待: 実行時アセット種別::チャンク目録.番号(),
                実際: 種別.番号(),
            })
        }
    }
}
