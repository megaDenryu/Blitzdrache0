//! カタログを共通ヘッダーへ格納し、検証して復元する。版ごとの読み取りをここで分岐し、旧版は版固有の型で読んでから最新版へ変換する。
//! 書き出しは常に最新版で行い版を選ぶ引数を持たない。
//! 参照: `_doc/設計/アセット実行時形式.md`

mod bytes;
mod v1;
mod v2;
mod v3;

use super::{
    アセット実行時形式エラー, アセット形式版, 実行時アセットを格納する, 実行時アセットを開く, 実行時アセット種別
};
use crate::asset::catalog::カタログ;

pub fn カタログを実行時形式へ格納する(カタログ: &カタログ) -> Result<Vec<u8>, アセット実行時形式エラー> {
    let 内容 = v3::カタログ内容を書く(カタログ)?;
    実行時アセットを格納する(アセット形式版::V3, 実行時アセット種別::カタログ, &内容)
}

pub fn 実行時形式からカタログを読む(バイト列: &[u8]) -> Result<カタログ, アセット実行時形式エラー> {
    let アセット = 実行時アセットを開く(バイト列)?;
    match アセット.種別 {
        実行時アセット種別::カタログ => match アセット.形式版 {
            アセット形式版::V1 => v1::カタログ内容を読む(アセット.内容),
            アセット形式版::V2 => v2::カタログ内容を読む(アセット.内容),
            アセット形式版::V3 => v3::カタログ内容を読む(アセット.内容),
            版 @ (アセット形式版::V4 | アセット形式版::V5) => Err(アセット実行時形式エラー::未対応形式版(版.番号())),
        },
        種別 @ (実行時アセット種別::シーン | 実行時アセット種別::チャンク目録 | 実行時アセット種別::高さ場) => {
            Err(アセット実行時形式エラー::アセット種別不一致 {
                期待: 実行時アセット種別::カタログ.番号(),
                実際: 種別.番号(),
            })
        }
    }
}
