//! 版1の静的シーン内容を共通ヘッダーへ格納し、検証して復元する。

pub(super) mod bytes;
pub(crate) mod mesh_layout;
mod read;
mod write;

use super::{
    アセット実行時形式エラー, 実行時アセットを格納する, 実行時アセットを開く, 実行時アセット種別
};
use crate::asset::scene_data::シーンデータ;

pub fn シーンを実行時形式へ格納する(シーン: &シーンデータ) -> Result<Vec<u8>, アセット実行時形式エラー> {
    let 内容 = write::内容を書く(シーン)?;
    実行時アセットを格納する(実行時アセット種別::シーン, &内容)
}

pub fn 実行時形式からシーンを読む(バイト列: &[u8]) -> Result<シーンデータ, アセット実行時形式エラー> {
    let アセット = 実行時アセットを開く(バイト列)?;
    match アセット.種別 {
        実行時アセット種別::シーン => read::内容を読む(アセット.内容),
        種別 @ (実行時アセット種別::カタログ | 実行時アセット種別::チャンク目録) => {
            Err(アセット実行時形式エラー::アセット種別不一致 {
                期待: 実行時アセット種別::シーン.番号(),
                実際: 種別.番号(),
            })
        }
    }
}
