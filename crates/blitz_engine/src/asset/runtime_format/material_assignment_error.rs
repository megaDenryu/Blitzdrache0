//! 1つのメッシュを材質で塗り分ける並び、つまりプリミティブ列と材質集合の検査が返す失敗型。
//! 版4で加わった条件をこの型が所有し、共通ヘッダーや頂点・スキン・アニメーションの検査と語彙を混ぜない。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「入力契約と実行時形式(scene v4)」

#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum 材質割当エラー {
    #[error("メッシュには1プリミティブ以上が必要である")]
    プリミティブなし,
    #[error("プリミティブのインデックス数が0である")]
    空のプリミティブ,
    #[error("プリミティブの区間(開始{開始}・件数{件数})がインデックス数{インデックス数}の範囲外である")]
    区間範囲外 {
        開始: usize, 件数: usize, インデックス数: usize
    },
    #[error("プリミティブの頂点基準を加えた頂点番号{頂点番号}が頂点数{頂点数}の範囲外である")]
    頂点範囲外 { 頂点番号: u32, 頂点数: usize },
    #[error("プリミティブが参照する材質スロットID {番号}が材質集合に存在しない")]
    材質スロット未定義 { 番号: u32 },
    #[error("この版は全インデックスを材質スロット0で塗る1件のプリミティブ列しか表せないが、プリミティブ数は{プリミティブ数}である")]
    旧版が表せないプリミティブ列 { プリミティブ数: usize },
    #[error("この版は材質スロット0の単一材質しか表せないが、材質数は{材質数}である")]
    旧版が表せない材質集合 { 材質数: usize },
    #[error("材質集合が条件を満たさない: {0}")]
    材質集合不正(crate::asset::material_set_error::材質集合エラー),
    #[error("材質特徴集合が条件を満たさない: {0}")]
    材質特徴集合不正(crate::asset::pbr_material_data::材質特徴集合エラー),
}
