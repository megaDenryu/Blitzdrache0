//! 一辺と項目を決定的な座標順で版2のチャンク目録へ書く。

use super::super::scene::bytes::書込先;
use super::super::アセット実行時形式エラー;
use crate::streaming::チャンク目録;

pub(super) fn チャンク目録内容を書く(目録: &チャンク目録) -> Result<Vec<u8>, アセット実行時形式エラー> {
    let mut 一覧: Vec<_> = 目録.全登録を走査する().collect();
    一覧.sort_by_key(|(チャンク, _)| (チャンク.x(), チャンク.z()));
    let mut 出力 = 書込先::新規();
    出力.f32(目録.一辺().f32値())?;
    出力.件数(一覧.len())?;
    for (チャンク, アセット) in 一覧 {
        出力.u64(チャンク.番号を返す());
        let 文字列 = アセット.文字列を返す();
        出力.件数(文字列.len())?;
        出力.バイト列(文字列.as_bytes());
    }
    Ok(出力.完了する())
}
