//! アセット実行時形式の形式版と、共通ヘッダーが運ぶ番号との対応。担当するのは、読み書きできる版を
//! 数え上げることと、番号との相互の写しを1箇所で持つことである。
//!
//! 版の意味が種別ごとに違うのは、1つの共通ヘッダーを4つの種別が共有しているためである。枝の説明が
//! 「シーンでは〜、カタログでは〜」の形になるのはそのためであり、種別ごとに版番号を分けてはいない。
//!
//! 各版が加えたものは次のとおりである。V2はシーンでは描画対象が持つ形状の判別値、カタログでは容量メタデータの個体数である。
//! V3はシーンでは形状の判別へ加えたインスタンス群、カタログでは容量メタデータの意味をテクスチャ格納バイト数へ変えたものである。
//! V4はシーンではメッシュが持つプリミティブ列と材質集合、カタログでは世界の由来と高さ場標本数である。
//! V5はテクスチャが持つ格納形式と縮小段の列であり、V6は材質1件が持つ地表の層の重ね合わせの種別である。V5とV6はシーンだけが使う。
//!
//! 注意: 番号は焼いたファイルの中に残るため、既存の枝の番号を付け替えてはならない。

use super::アセット実行時形式エラー;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum アセット形式版 {
    V1,
    V2, // シーンは形状の判別値、カタログは個体数
    V3, // シーンはインスタンス群、カタログはテクスチャ格納バイト数
    V4, // シーンはプリミティブ列と材質集合、カタログは世界の由来と高さ場標本数
    V5, // テクスチャの格納形式と縮小段の列
    V6, // 材質が持つ地表の層の重ね合わせの種別
}

impl アセット形式版 {
    pub fn 番号(self) -> u32 {
        match self {
            Self::V1 => 1,
            Self::V2 => 2,
            Self::V3 => 3,
            Self::V4 => 4,
            Self::V5 => 5,
            Self::V6 => 6,
        }
    }

    pub(super) fn 番号から読む(番号: u32) -> Result<Self, アセット実行時形式エラー> {
        match 番号 {
            1 => Ok(Self::V1),
            2 => Ok(Self::V2),
            3 => Ok(Self::V3),
            4 => Ok(Self::V4),
            5 => Ok(Self::V5),
            6 => Ok(Self::V6),
            未対応 => Err(アセット実行時形式エラー::未対応形式版(未対応)),
        }
    }
}
