//! アセット実行時形式の形式版と、共通ヘッダーが運ぶ番号との対応。担当するのは、読み書きできる版を
//! 数え上げることと、番号との相互の写しを1箇所で持つことである。
//!
//! 版の意味が種別ごとに違うのは、1つの共通ヘッダーを4つの種別が共有しているためである。枝の説明が
//! 「シーンでは〜、カタログでは〜」の形になるのはそのためであり、種別ごとに版番号を分けてはいない。
//!
//! 注意: 番号は焼いたファイルの中に残るため、既存の枝の番号を付け替えてはならない。

use super::アセット実行時形式エラー;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum アセット形式版 {
    V1,
    /// シーンでは描画対象が形状の判別値を持つ版、カタログでは容量メタデータへ個体数を加えた版である。
    V2,
    /// シーンでは形状の判別へインスタンス群を加えた版、カタログでは容量メタデータの意味をテクスチャ格納バイト数へ変えた版である。
    V3,
    /// シーンではメッシュへプリミティブ列と材質集合を、カタログでは世界の由来と高さ場標本数を加えた版である。
    V4,
    /// テクスチャへ格納形式と縮小段の列を加えた版。シーンだけがこの版を使う。
    V5,
}

impl アセット形式版 {
    pub fn 番号(self) -> u32 {
        match self {
            Self::V1 => 1,
            Self::V2 => 2,
            Self::V3 => 3,
            Self::V4 => 4,
            Self::V5 => 5,
        }
    }

    pub(super) fn 番号から読む(番号: u32) -> Result<Self, アセット実行時形式エラー> {
        match 番号 {
            1 => Ok(Self::V1),
            2 => Ok(Self::V2),
            3 => Ok(Self::V3),
            4 => Ok(Self::V4),
            5 => Ok(Self::V5),
            未対応 => Err(アセット実行時形式エラー::未対応形式版(未対応)),
        }
    }
}
