//! 版1チャンク目録内容を境界検査し、座標の重複を拒否して復元する。

use super::super::scene_v1::bytes::読取位置;
use super::super::アセット実行時形式エラー;
use crate::asset::id::アセットID;
use crate::streaming::チャンク目録;
use crate::チャンク座標;

/// 座標のu64表現8バイトと、アセットIDの長さ4バイト。
const 項目最小長: usize = 12;

pub(super) fn 内容を読む(内容: &[u8]) -> Result<チャンク目録, アセット実行時形式エラー> {
    let mut 入力 = 読取位置::新規(内容);
    let 項目数 = 入力.件数(項目最小長)?;
    let mut 目録 = チャンク目録::空を作る();
    for _ in 0..項目数 {
        let 番号 = 入力.u64()?;
        let 長さ = 入力.usize()?;
        let 文字列 = std::str::from_utf8(入力.バイト列(長さ)?).map_err(|_| アセット実行時形式エラー::不正な文字列)?;
        let アセット = アセットID::生成する(文字列).map_err(|_| アセット実行時形式エラー::不正な文字列)?;
        目録
            .登録する(チャンク座標::番号から復元する(番号), アセット)
            .map_err(|_| アセット実行時形式エラー::チャンク目録座標重複(番号))?;
    }
    入力.完了を検査する()?;
    Ok(目録)
}
