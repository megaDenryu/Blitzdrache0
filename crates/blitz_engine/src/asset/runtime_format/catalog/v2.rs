//! 版2のカタログと、最新版への変換。版2の容量メタデータのテクスチャの欄は展開済みテクスチャの合計バイト数であり、
//! 版3のテクスチャ格納バイト数とは意味が違う。並びは版3と同じであるため、版で違うのはこの欄の意味だけである。
//! 版2専用のメタデータ型を残して変換で最新版へ写すため、最新版の型に「版2のテクスチャの欄は別の意味である」という分岐が入り込まない。
//! 参照: `_doc/設計/アセット実行時形式.md`「カタログ内容の版2」

#[cfg(test)]
mod conversion_tests;
#[cfg(test)]
