//! 版1のカタログと、最新版への変換。版1の容量メタデータは頂点数・インデックス数・展開済みテクスチャバイト数の3つだけを持ち、個体数を持たない。
//! 版1専用のメタデータ型を残して変換で最新版へ写すため、最新版の型に「版1にはこの欄が無い」という分岐が入り込まない。

