/// 版1の容量メタデータ。u64を3つ持つ。テクスチャの欄は版2と同じく展開済みで数えたバイト数である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct メタデータV1 {
    頂点数: u64,
    インデックス数: u64,
    展開済みテクスチャバイト数: u64,
}

impl メタデータV1 {
    /// 版1はインスタンス群を表せないシーン形式と同じ時期の版であるため、個体数は0が正しい値である。
    fn 最新へ変換する(self) -> アセットメタデータ {
        アセットメタデータ {
            頂点数: self.頂点数,
            インデックス数: self.インデックス数,
            テクスチャ格納バイト数: self.展開済みテクスチャバイト数,
            個体数: 0,
            高さ場の標本数: 高さ場の標本数::生成する(0),
        }
    }
}

/// 版1の項目1件の最小バイト数。メタデータ以外の最小長へu64を3つ足した値である。
const 項目最小長: usize = bytes::メタデータ以外の項目最小長 + 24;

pub(super) fn カタログ内容を読む(内容: &[u8]) -> Result<カタログ, アセット実行時形式エラー> {
    let mut 入力 = 読取位置::新規(内容);
    let 項目数 = 入力.件数(項目最小長)?;
    let mut id一覧 = HashSet::with_capacity(項目数);
    let mut カタログ = カタログ::空を作る();
    for _ in 0..項目数 {
        let (id文字列, id, 実行時パス, 依存一覧) = bytes::項目本体を読む(&mut 入力)?;
        if !id一覧.insert(id文字列) {
            return Err(アセット実行時形式エラー::カタログID重複);
        }
        let メタデータ = メタデータV1 {
            頂点数: 入力.u64()?,
            インデックス数: 入力.u64()?,
            展開済みテクスチャバイト数: 入力.u64()?,
        };
        カタログ.詳細を登録する(id, 実行時パス, 依存一覧, メタデータ.最新へ変換する());
    }
    入力.完了を検査する()?;
    Ok(カタログ)
}
