//! カタログ項目のうち版で変わらない部分(安定ID・実行時パス・ソース依存一覧)の読み書き。
//! 版で変わるのは末尾の容量メタデータだけであるため、それ以外の並びを決める箇所をここ1つに閉じる。

use std::path::{Path, PathBuf};

use super::super::scene::bytes::{書込先, 読取位置};
use super::super::アセット実行時形式エラー;
use crate::asset::{catalog_entry::カタログ項目, id::アセットID};

/// 容量メタデータを除いた項目1件の最小バイト数。ID長4 + パス長4 + 依存数4に、最短のIDとパスを足した値である。
pub(super) const メタデータ以外の項目最小長: usize = 14;

pub(super) fn 項目本体を読む(
    入力: &mut 読取位置<'_>,
) -> Result<(String, アセットID, PathBuf, Vec<PathBuf>), アセット実行時形式エラー> {
    let id文字列 = 文字列を読む(入力)?.to_string();
    let id = アセットID::生成する(&id文字列).map_err(|_| アセット実行時形式エラー::不正な文字列)?;
    let 実行時パス = PathBuf::from(文字列を読む(入力)?);
    let 依存数 = 入力.件数(5)?;
    let mut 依存一覧 = Vec::with_capacity(依存数);
    for _ in 0..依存数 {
        依存一覧.push(PathBuf::from(文字列を読む(入力)?));
    }
    Ok((id文字列, id, 実行時パス, 依存一覧))
}

pub(super) fn 項目本体を書く(
    出力: &mut 書込先, id: &アセットID, 項目: &カタログ項目
) -> Result<(), アセット実行時形式エラー> {
    文字列を書く(出力, id.文字列を返す())?;
    パスを書く(出力, 項目.実行時パス())?;
    出力.件数(項目.ソース依存一覧().len())?;
    for 依存 in 項目.ソース依存一覧() {
        パスを書く(出力, 依存)?;
    }
    Ok(())
}

/// 安定IDの昇順に並べた全項目。集合を決定的なバイト列にする唯一の順序である。
pub(super) fn 安定id順に並べる(カタログ: &crate::asset::catalog::カタログ) -> Vec<(&アセットID, &カタログ項目)> {
    let mut 一覧: Vec<_> = カタログ.全項目を走査する().collect();
    一覧.sort_by(|(左, _), (右, _)| 左.文字列を返す().cmp(右.文字列を返す()));
    一覧
}

fn 文字列を読む<'a>(入力: &mut 読取位置<'a>) -> Result<&'a str, アセット実行時形式エラー> {
    let 長さ = 入力.usize()?;
    std::str::from_utf8(入力.バイト列(長さ)?).map_err(|_| アセット実行時形式エラー::不正な文字列)
}

fn パスを書く(出力: &mut 書込先, パス: &Path) -> Result<(), アセット実行時形式エラー> {
    let 文字列 = パス.to_str().ok_or(アセット実行時形式エラー::不正なパス)?.replace('\\', "/");
    文字列を書く(出力, &文字列)
}

fn 文字列を書く(出力: &mut 書込先, 値: &str) -> Result<(), アセット実行時形式エラー> {
    出力.件数(値.len())?;
    出力.バイト列(値.as_bytes());
    Ok(())
}
