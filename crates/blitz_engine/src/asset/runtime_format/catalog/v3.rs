//! 版3のカタログ。容量メタデータのテクスチャの欄をテクスチャ格納バイト数にした最新版であり、読み取り結果は変換を挟まずそのまま`カタログ`である。
//! 並びは版2と同じであり、変わったのは同じ位置の同じ幅の数値の意味だけである。それでも版を切るのは、旧い意味のまま読むとVRAMの見積が静かに誤るためである。
//! 参照: `_doc/設計/アセット実行時形式.md`「カタログ内容の版3」

use std::collections::HashSet;

use super::super::scene::bytes::{書込先, 読取位置};
use super::super::アセット実行時形式エラー;
use super::bytes;
use crate::asset::{asset_metadata::アセットメタデータ, catalog::カタログ};

/// 版3の項目1件の最小バイト数。メタデータ以外の最小長へu64を4つ足した値である。
const 項目最小長: usize = bytes::メタデータ以外の項目最小長 + 32;

pub(super) fn 内容を読む(内容: &[u8]) -> Result<カタログ, アセット実行時形式エラー> {
    let mut 入力 = 読取位置::新規(内容);
    let 項目数 = 入力.件数(項目最小長)?;
    let mut id一覧 = HashSet::with_capacity(項目数);
    let mut カタログ = カタログ::空を作る();
    for _ in 0..項目数 {
        let (id文字列, id, 実行時パス, 依存一覧) = bytes::項目本体を読む(&mut 入力)?;
        if !id一覧.insert(id文字列) {
            return Err(アセット実行時形式エラー::カタログID重複);
        }
        let メタデータ = アセットメタデータ {
            頂点数: 入力.u64()?,
            インデックス数: 入力.u64()?,
            テクスチャバイト数: 入力.u64()?,
            個体数: 入力.u64()?,
        };
        カタログ.詳細を登録する(id, 実行時パス, 依存一覧, メタデータ);
    }
    入力.完了を検査する()?;
    Ok(カタログ)
}

pub(super) fn 内容を書く(カタログ: &カタログ) -> Result<Vec<u8>, アセット実行時形式エラー> {
    let 一覧 = bytes::安定id順に並べる(カタログ);
    let mut 出力 = 書込先::新規();
    出力.件数(一覧.len())?;
    for (id, 項目) in 一覧 {
        bytes::項目本体を書く(&mut 出力, id, 項目)?;
        let メタデータ = 項目.メタデータ();
        出力.u64(メタデータ.頂点数);
        出力.u64(メタデータ.インデックス数);
        出力.u64(メタデータ.テクスチャバイト数);
        出力.u64(メタデータ.個体数);
    }
    Ok(出力.完了する())
}
