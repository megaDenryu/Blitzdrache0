//! 版4のカタログ。世界の由来と高さ場の標本数を持つ最新版。

use std::collections::HashSet;

use super::super::scene::bytes::{書込先, 読取位置};
use super::super::アセット実行時形式エラー;
use super::bytes;
use crate::asset::{
    アセットメタデータ, カタログ, 世界の乱数の種, 世界の生成器の版, 世界の由来, 高さ場の標本数
};

const 由来なし: u32 = 0;
const 種から生成: u32 = 1;
const 項目最小長: usize = bytes::メタデータ以外の項目最小長 + 40;

pub(super) fn カタログ内容を読む(内容: &[u8]) -> Result<カタログ, アセット実行時形式エラー> {
    let mut 入力 = 読取位置::新規(内容);
    let 世界の由来 = 由来を読む(&mut 入力)?;
    let 項目数 = 入力.件数(項目最小長)?;
    let mut id一覧 = HashSet::with_capacity(項目数);
    let mut カタログ = カタログ::空を作る();
    カタログ.世界の由来を記録する(世界の由来);
    for _ in 0..項目数 {
        let (id文字列, id, 実行時パス, 依存一覧) = bytes::項目本体を読む(&mut 入力)?;
        if !id一覧.insert(id文字列) {
            return Err(アセット実行時形式エラー::カタログID重複);
        }
        let メタデータ = アセットメタデータ {
            頂点数: 入力.u64()?,
            インデックス数: 入力.u64()?,
            テクスチャ格納バイト数: 入力.u64()?,
            個体数: 入力.u64()?,
            高さ場の標本数: 高さ場の標本数::生成する(入力.u64()?),
        };
        カタログ.詳細を登録する(id, 実行時パス, 依存一覧, メタデータ);
    }
    入力.完了を検査する()?;
    Ok(カタログ)
}

pub(super) fn カタログ内容を書く(カタログ: &カタログ) -> Result<Vec<u8>, アセット実行時形式エラー> {
    let mut 出力 = 書込先::新規();
    由来を書く(&mut 出力, カタログ.世界の由来());
    let 一覧 = bytes::安定id順に並べる(カタログ);
    出力.件数(一覧.len())?;
    for (id, 項目) in 一覧 {
        bytes::項目本体を書く(&mut 出力, id, 項目)?;
        let m = 項目.メタデータ();
        出力.u64(m.頂点数);
        出力.u64(m.インデックス数);
        出力.u64(m.テクスチャ格納バイト数);
        出力.u64(m.個体数);
        出力.u64(m.高さ場の標本数.値());
    }
    Ok(出力.完了する())
}

fn 由来を書く(出力: &mut 書込先, 由来: 世界の由来) {
    match 由来 {
        世界の由来::生成による由来を持たない => {
            出力.u32(由来なし);
            出力.u32(0);
            出力.u32(0);
        }
        世界の由来::種から生成した {
            乱数の種, 生成器の版
        } => {
            出力.u32(種から生成);
            出力.u32(乱数の種.値());
            出力.u32(生成器の版.値());
        }
    }
}

fn 由来を読む(入力: &mut 読取位置<'_>) -> Result<世界の由来, アセット実行時形式エラー> {
    let 判別 = 入力.u32()?;
    let 種 = 入力.u32()?;
    let 版 = 入力.u32()?;
    match 判別 {
        由来なし if 種 == 0 && 版 == 0 => Ok(世界の由来::生成による由来を持たない),
        種から生成 if 版 > 0 => Ok(世界の由来::種から生成した {
            乱数の種: 世界の乱数の種::生成する(種),
            生成器の版: 世界の生成器の版::生成する(版),
        }),
        種から生成 => Err(アセット実行時形式エラー::未知の世界の由来(判別)),
        _ => Err(アセット実行時形式エラー::未知の世界の由来(判別)),
    }
}
