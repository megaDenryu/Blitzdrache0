//! カタログ項目を安定ID順に並べ、版1内容へ決定的に書く。

use std::path::Path;

use super::super::scene_v1::bytes::書込先;
use super::super::アセット実行時形式エラー;
use crate::asset::{catalog::カタログ, catalog_entry::カタログ項目};

pub(super) fn 内容を書く(カタログ: &カタログ) -> Result<Vec<u8>, アセット実行時形式エラー> {
    let mut 一覧: Vec<_> = カタログ.全項目を走査する().collect();
    一覧.sort_by(|(左, _), (右, _)| 左.文字列を返す().cmp(右.文字列を返す()));
    let mut 出力 = 書込先::新規();
    出力.件数(一覧.len())?;
    for (id, 項目) in 一覧 {
        文字列を書く(&mut 出力, id.文字列を返す())?;
        パスを書く(&mut 出力, 項目.実行時パス())?;
        依存一覧を書く(&mut 出力, 項目)?;
        let メタデータ = 項目.メタデータ();
        出力.u64(メタデータ.頂点数);
        出力.u64(メタデータ.インデックス数);
        出力.u64(メタデータ.テクスチャバイト数);
    }
    Ok(出力.完了する())
}

fn 依存一覧を書く(出力: &mut 書込先, 項目: &カタログ項目) -> Result<(), アセット実行時形式エラー> {
    出力.件数(項目.ソース依存一覧().len())?;
    for 依存 in 項目.ソース依存一覧() {
        パスを書く(出力, 依存)?;
    }
    Ok(())
}

fn パスを書く(出力: &mut 書込先, パス: &Path) -> Result<(), アセット実行時形式エラー> {
    let 文字列 = パス.to_str().ok_or(アセット実行時形式エラー::不正なパス)?.replace('\\', "/");
    文字列を書く(出力, &文字列)
}

fn 文字列を書く(出力: &mut 書込先, 値: &str) -> Result<(), アセット実行時形式エラー> {
    出力.件数(値.len())?;
    出力.バイト列(値.as_bytes());
    Ok(())
}
