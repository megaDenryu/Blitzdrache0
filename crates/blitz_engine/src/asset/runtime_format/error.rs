//! アセット実行時形式の共通ヘッダー検査で返す失敗型。

#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum アセット実行時形式エラー {
    #[error("アセット実行時形式のヘッダーが24バイト未満だった: {実長}バイト")]
    ヘッダー不足 { 実長: usize },
    #[error("アセット実行時形式の固定識別値が一致しない")]
    固定識別値不一致,
    #[error("未対応のアセット実行時形式版だった: {0}")]
    未対応形式版(u32),
    #[error("未知の実行時アセット種別だった: {0}")]
    未知のアセット種別(u32),
    #[error("内容長をu64で表現できない")]
    内容長表現不能,
    #[error("アセット実行時形式の宣言内容長{宣言長}バイトと実長{実長}バイトが一致しない")]
    内容長不一致 { 宣言長: u64, 実長: u64 },
    #[error("アセット実行時形式の内容が途中で終わった")]
    内容終端,
    #[error("アセット実行時形式に未読の末尾が{0}バイト残った")]
    未読末尾(usize),
    #[error("アセット実行時形式の件数をu32で表現できない")]
    件数表現不能,
    #[error("アセット実行時形式の宣言件数{宣言件数}が残り{残りバイト数}バイトを超える")]
    件数過大 { 宣言件数: usize, 残りバイト数: usize },
    #[error("アセット実行時形式の長さを実行環境のusizeで表現できない")]
    長さ表現不能,
    #[error("アセット実行時形式に非有限の小数が含まれる")]
    非有限小数,
    #[error("シーン内容に描画対象が存在しない")]
    描画対象なし,
    #[error("シーン内容で描画対象ID {0}が重複している")]
    描画対象ID重複(u64),
    #[error("未知のマテリアル種別だった: {0}")]
    未知のマテリアル種別(u32),
    #[error("金属粗さPBRの係数が0以上1以下の範囲外だった")]
    マテリアル係数範囲外,
    #[error("不正な有無判別値だった: {0}")]
    不正な有無判別値(u8),
    #[error("テクスチャの宣言RGBA8長{期待長}バイトと実長{実長}バイトが一致しない")]
    テクスチャ長不一致 { 期待長: u64, 実長: u64 },
    #[error("テクスチャの幅と高さは1以上でなければならない")]
    テクスチャ寸法ゼロ,
    #[error("メッシュには1頂点以上が必要である")]
    頂点なし,
    #[error("メッシュには1インデックス以上が必要である")]
    インデックスなし,
    #[error("インデックス{インデックス}が頂点数{頂点数}の範囲外である")]
    インデックス範囲外 { インデックス: u32, 頂点数: usize },
    #[error("版1のスキン内容はまだ実装されていない")]
    スキン内容未実装,
    #[error("版1のアニメーション内容はまだ実装されていない")]
    アニメーション内容未実装,
}
