//! 版6のシーン。材質1件が金属粗さPBRと地表の層の重ね合わせの2つの種別を表せる。
//! これが最新版であるため、読み取り結果は変換を挟まずそのまま`シーンデータ`である。
//! 描画対象の並びは版5と同じであり、共有の並びへ版6の要素の読み方と書き方を渡す。
//! 参照: `_doc/設計/アセット実行時形式.md`「シーン内容の版6」

#[cfg(test)]
mod roundtrip_tests;

use super::super::{アセット実行時形式エラー, アセット形式版, 実行時アセットを格納する, 実行時アセット種別};
use super::multi_material_body;
use super::read_element::版ごとの要素の読み方;
use super::write_element::版ごとの要素の書き方;
use crate::asset::scene_data::シーンデータ;

pub(super) fn シーン内容を格納する(シーン: &シーンデータ) -> Result<Vec<u8>, アセット実行時形式エラー> {
    let 内容 = multi_material_body::マルチマテリアル本体を書く(シーン, 版ごとの要素の書き方::版6())?;
    実行時アセットを格納する(アセット形式版::V6, 実行時アセット種別::シーン, &内容)
}

pub(super) fn シーン内容を読む(内容: &[u8]) -> Result<シーンデータ, アセット実行時形式エラー> {
    multi_material_body::マルチマテリアル本体を読む(内容, 版ごとの要素の読み方::版6())
}
