//! 静的物理形状を持つシーンが版7の実行時形式を決定的に往復することの検査。
//! 材料は`static_shape::shape_fixture`が持ち、焼く側と読む側が同じ形を使う。

#![allow(clippy::unwrap_used)]

use crate::asset::runtime_scene_tests::静的シーンを作る;
use crate::asset::{
    アセット実行時形式エラー, シーンを実行時形式へ格納する, シーンデータ, 実行時形式からシーンを読む
};
use crate::static_shape::shape_fixture::{建物1棟の形状を作る, 綴り一覧から形状を作る};
use crate::static_shape::静的物理形状エラー;

fn 形状を持つシーン(綴り一覧: &[&str]) -> シーンデータ {
    静的シーンを作る(vec![10, 20, 30, 255], 0.2).静的物理形状を添える(綴り一覧から形状を作る(綴り一覧))
}

#[test]
fn 静的物理形状を持つシーンを決定的に往復する() {
    let シーン = 形状を持つシーン(&["酒場"]);
    let 一回目 = シーンを実行時形式へ格納する(&シーン).unwrap();
    let 二回目 = シーンを実行時形式へ格納する(&シーン).unwrap();
    assert_eq!(一回目, 二回目);
    assert_eq!(実行時形式からシーンを読む(&一回目), Ok(シーン));
}

#[test]
fn 往復した直方体の値と識別子が入力と一致する() {
    let 焼いた = シーンを実行時形式へ格納する(&形状を持つシーン(&["酒場"])).unwrap();
    let 読んだ = 実行時形式からシーンを読む(&焼いた).unwrap();
    let 形状 = 読んだ.静的物理形状();
    assert_eq!((形状.衝突対象数(), 形状.子形状の総数()), (1, 2));
    assert_eq!(形状.衝突対象一覧(), 建物1棟の形状を作る("酒場").衝突対象一覧());
}

/// 綴りの長さが同じ2棟を焼いてから、後の綴りを先の綴りへ書き換える。件数も並びも変わらないため、
/// 読み取り側が重複そのものを見ていなければ通ってしまうバイト列になる。
#[test]
fn 安定識別子が重複したバイト列を読み取りが拒む() {
    let mut 焼いた = シーンを実行時形式へ格納する(&形状を持つシーン(&["酒場A", "酒場B"])).unwrap();
    let 位置 = 焼いた.windows(7).position(|窓| 窓 == "酒場B".as_bytes()).unwrap();
    焼いた[位置..位置 + 7].copy_from_slice("酒場A".as_bytes());
    assert_eq!(
        実行時形式からシーンを読む(&焼いた),
        Err(アセット実行時形式エラー::静的物理形状不正(
            静的物理形状エラー::安定識別子が重複する
        ))
    );
}
