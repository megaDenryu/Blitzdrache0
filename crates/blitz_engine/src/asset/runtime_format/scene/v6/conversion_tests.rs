//! 版6で焼かれたシーンが最新版の型へ変換されて読めることの検査。版6の書き出しは検査だけが持つため、材料もここで作る。
//! 版6から版7への昇格が恒等であること、つまり静的物理形状を持たないシーンでは内容のバイト列が一致し、
//! 違いが共通ヘッダーの形式版だけであることをここで固定する。
//!
//! 版6が静的物理形状を表せないことも見る。焼いた形状を黙って落とさず型付きで拒む枝である。

#![allow(clippy::unwrap_used)]

use super::super::super::{アセット形式版, 実行時アセットを格納する, 実行時アセット種別};
use crate::asset::runtime_format::実行時形式からシーンを読む;
use crate::asset::runtime_scene_tests::静的シーンを作る;
use crate::asset::アセット実行時形式エラー;
use crate::static_shape::shape_fixture::建物1棟の形状を作る;
use crate::static_shape::静的物理形状エラー;

fn 材料のシーン() -> crate::asset::シーンデータ {
    静的シーンを作る(vec![10, 20, 30, 255], 0.2)
}

fn 版6バイト列を作る() -> Vec<u8> {
    let 内容 = super::シーン内容を書く(&材料のシーン()).unwrap();
    実行時アセットを格納する(アセット形式版::V6, 実行時アセット種別::シーン, &内容).unwrap()
}

#[test]
fn 版6のシーンを最新版へ変換して読む() {
    assert_eq!(実行時形式からシーンを読む(&版6バイト列を作る()).unwrap(), 材料のシーン());
}

#[test]
fn 版6と最新版の違いは共通ヘッダーの形式版だけである() {
    let 版6 = 版6バイト列を作る();
    let 最新版 = crate::asset::シーンを実行時形式へ格納する(&材料のシーン()).unwrap();
    assert_eq!(版6[8..12], アセット形式版::V6.番号().to_le_bytes());
    assert_eq!(最新版[8..12], アセット形式版::V7.番号().to_le_bytes());
    assert_eq!(版6[..8], 最新版[..8]);
    // 版7が足すのは末尾の「衝突対象0件」を表す4バイトだけであり、その手前は1バイトも変わらない。
    assert_eq!(版6[24..], 最新版[24..最新版.len() - 4]);
    assert_eq!(最新版[最新版.len() - 4..], 0_u32.to_le_bytes());
}

#[test]
fn 版6は静的物理形状を表せない() {
    let シーン = 材料のシーン().静的物理形状を添える(建物1棟の形状を作る("酒場"));
    assert_eq!(
        super::シーン内容を書く(&シーン),
        Err(アセット実行時形式エラー::静的物理形状不正(
            静的物理形状エラー::節を持たない旧版で焼こうとした
        ))
    );
    assert!(crate::asset::シーンを実行時形式へ格納する(&シーン).is_ok());
}
