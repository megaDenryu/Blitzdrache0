//! 地表の層の重ね合わせの材質を持つシーンが、版6の実行時形式を決定的に往復することの検査。
//! 材料は`scene::surface_layer_fixture`が持ち、生成が拒む値の数え上げはこのファイルが持つ。

#![allow(clippy::unwrap_used)]

use super::super::surface_layer_fixture::{
    地表の層の重ね合わせの静的シーンを作る, 層ごとのタイル倍率, 非対称な重みの画素列
};
use crate::asset::runtime_scene_tests::原寸だけのrgba8テクスチャを作る;
use crate::asset::{
    シーンを実行時形式へ格納する, マテリアルデータ, 地表の層の重ね合わせデータ, 地表の層の重ね合わせデータエラー, 実行時形式からシーンを読む,
};

#[test]
fn 地表の層の重ね合わせのシーンを決定的に往復する() {
    let シーン = 地表の層の重ね合わせの静的シーンを作る();
    let 一回目 = シーンを実行時形式へ格納する(&シーン).unwrap();
    let 二回目 = シーンを実行時形式へ格納する(&シーン).unwrap();
    assert_eq!(一回目, 二回目);
    assert_eq!(実行時形式からシーンを読む(&一回目), Ok(シーン));
}

#[test]
fn 往復した重みの画素とタイル倍率が入力と一致する() {
    let 焼いた = シーンを実行時形式へ格納する(&地表の層の重ね合わせの静的シーンを作る()).unwrap();
    let 読んだ = 実行時形式からシーンを読む(&焼いた).unwrap();
    let マテリアルデータ::地表の層の重ね合わせ(データ) = &読んだ.先頭の描画対象().材質集合().割当一覧()[0].マテリアル
    else {
        panic!("地表の層の重ね合わせの枝で読めなかった");
    };
    assert_eq!(データ.重みテクスチャ().段ごとのバイト列を返す(), [非対称な重みの画素列()]);
    assert_eq!(データ.層ごとのタイル倍率(), 層ごとのタイル倍率());
    assert_eq!(データ.粗さ係数(), 0.9);
}

#[test]
fn 正でないタイル倍率を持つ材質を作れない() {
    let 結果 = 地表の層の重ね合わせデータ::生成する(
        原寸だけのrgba8テクスチャを作る(1, 1, vec![255, 0, 0, 0]),
        [1.0, 0.0, 1.0, 1.0],
        0.0,
        0.5,
    );
    assert_eq!(
        結果.err(),
        Some(地表の層の重ね合わせデータエラー::タイル倍率が正の有限値でない { 層番号: 1 })
    );
}

#[test]
fn 範囲の外の係数を持つ材質を作れない() {
    let 結果 = 地表の層の重ね合わせデータ::生成する(原寸だけのrgba8テクスチャを作る(1, 1, vec![255, 0, 0, 0]), [1.0; 4], 0.0, 1.5);
    assert_eq!(
        結果.err(),
        Some(地表の層の重ね合わせデータエラー::係数範囲外 {
            係数の名前: "粗さ係数"
        })
    );
}
