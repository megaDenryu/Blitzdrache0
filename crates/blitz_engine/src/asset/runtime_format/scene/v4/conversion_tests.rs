//! 版4で焼かれたシーンが最新版の型へ変換されて読めることの検査。版4の書き出しは検査だけが持つため、材料もここで作る。
//! 版4のテクスチャは格納形式RGBA8で縮小段を1本だけ持つ値へ写る。これが版4から版5への昇格の変換である。

#![allow(clippy::unwrap_used)]

use super::super::super::{アセット形式版, 実行時アセットを格納する, 実行時アセット種別};
use crate::asset::runtime_format::実行時形式からシーンを読む;
use crate::asset::runtime_scene_tests::{ベースカラーを指定して静的シーンを作る, 静的シーンを作る};
use crate::asset::texture_storage::{テクスチャ格納形式, 格納済みテクスチャ};
use crate::asset::{マテリアルデータ, 材質割当エラー};

fn 版4バイト列を作る() -> Vec<u8> {
    let 内容 = super::シーン内容を書く(&静的シーンを作る(vec![10, 20, 30, 255], 0.2)).unwrap();
    実行時アセットを格納する(アセット形式版::V4, 実行時アセット種別::シーン, &内容).unwrap()
}

/// ベースカラーをブロック圧縮の値にしたシーン。4x4は1ブロックであり、縮小段は原寸の1本で連なりが尽きる。
fn ブロック圧縮の4x4を1段だけ持つテクスチャを作る() -> 格納済みテクスチャ {
    格納済みテクスチャ::生成する(4, 4, テクスチャ格納形式::BC1, vec![vec![0; 8]]).unwrap()
}

#[test]
fn 版4のシーンを最新版へ変換して読む() {
    let 読み取り = 実行時形式からシーンを読む(&版4バイト列を作る()).unwrap();
    assert_eq!(読み取り, 静的シーンを作る(vec![10, 20, 30, 255], 0.2));
}

#[test]
fn 版4のテクスチャは格納形式rgba8の1段として読める() {
    let 読み取り = 実行時形式からシーンを読む(&版4バイト列を作る()).unwrap();
    let マテリアルデータ::金属粗さPBR(材質) = 読み取り.先頭の描画対象().材質集合().割当一覧()[0].マテリアル.clone();
    let ベースカラー = 材質.ベースカラー.unwrap();
    assert_eq!(ベースカラー.格納形式を返す(), テクスチャ格納形式::RGBA8);
    assert_eq!(ベースカラー.段ごとのバイト列を返す(), [vec![10, 20, 30, 255]]);
}

#[test]
fn 版4と最新版で先頭のヘッダー形式版が異なる() {
    let 版4 = 版4バイト列を作る();
    let 最新版 = crate::asset::シーンを実行時形式へ格納する(&静的シーンを作る(vec![10, 20, 30, 255], 0.2)).unwrap();
    assert_eq!(版4[8..12], アセット形式版::V4.番号().to_le_bytes());
    assert_eq!(最新版[8..12], アセット形式版::V5.番号().to_le_bytes());
}

#[test]
fn 版4はブロック圧縮のテクスチャを表せない() {
    let シーン = ベースカラーを指定して静的シーンを作る(ブロック圧縮の4x4を1段だけ持つテクスチャを作る(), 0.2);
    assert_eq!(
        super::シーン内容を書く(&シーン),
        Err(材質割当エラー::旧版が表せないテクスチャ格納形式.into())
    );
    assert!(crate::asset::シーンを実行時形式へ格納する(&シーン).is_ok());
}
