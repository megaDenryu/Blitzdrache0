//! テクスチャ格納形式のバイト表現。版5の並びが格納形式を1バイトの判別値で持つため、値と枝の対応をこの1箇所が決める。
//! 形式の語彙そのものは`texture_storage`が持ち、ここが持つのはその語彙とファイル上の数の対応だけである。
//! 参照: `_doc/設計/アセット実行時形式.md`「シーン内容の版5」

use super::super::アセット実行時形式エラー;
use crate::asset::texture_storage::{テクスチャ格納形式, 格納済みテクスチャエラー};

const RGBA8の判別値: u8 = 0;
const BC1の判別値: u8 = 1;

pub(super) fn 判別値から格納形式を読む(判別値: u8) -> Result<テクスチャ格納形式, アセット実行時形式エラー> {
    match 判別値 {
        RGBA8の判別値 => Ok(テクスチャ格納形式::RGBA8),
        BC1の判別値 => Ok(テクスチャ格納形式::BC1),
        不正 => Err(格納済みテクスチャエラー::未知の格納形式の判別値(不正).into()),
    }
}

pub(super) fn 格納形式の判別値を返す(格納形式: テクスチャ格納形式) -> u8 {
    match 格納形式 {
        テクスチャ格納形式::RGBA8 => RGBA8の判別値,
        テクスチャ格納形式::BC1 => BC1の判別値,
    }
}
