//! 版3で焼かれたシーンが最新版の型へ変換されて読めることの検査。版3の書き出しは検査だけが持つため、材料もここで作る。
//! 版3は単一マテリアルしか持たないため、変換後は要素1件でスロット番号0の材質集合と、全インデックスを塗る1件のプリミティブ列になる。

#![allow(clippy::unwrap_used)]

use super::super::super::{アセット形式版, 実行時アセットを格納する, 実行時アセット種別};
use crate::asset::draw_shape::描画形状;
use crate::asset::runtime_format::実行時形式からシーンを読む;
use crate::asset::runtime_scene_multi_material_tests::fixture::二材質シーンを作る;
use crate::asset::runtime_scene_tests::静的シーンを作る;
use crate::asset::{アセット実行時形式エラー, 材質割当エラー};

fn 版3バイト列を作る() -> Vec<u8> {
    let 内容 = super::write::内容を書く(&静的シーンを作る(vec![10, 20, 30, 255], 0.2)).unwrap();
    実行時アセットを格納する(アセット形式版::V3, 実行時アセット種別::シーン, &内容).unwrap()
}

#[test]
fn 版3のシーンを最新版へ変換して読む() {
    let 読み取り = 実行時形式からシーンを読む(&版3バイト列を作る()).unwrap();
    assert_eq!(読み取り, 静的シーンを作る(vec![10, 20, 30, 255], 0.2));
    assert!(matches!(読み取り.先頭の描画対象().形状(), 描画形状::通常メッシュ(_)));
}

#[test]
fn 版3の単一マテリアルは要素1件の材質集合になる() {
    let 読み取り = 実行時形式からシーンを読む(&版3バイト列を作る()).unwrap();
    let 材質集合 = 読み取り.先頭の描画対象().材質集合();
    assert_eq!(材質集合.件数(), 1);
    assert_eq!(材質集合.割当一覧()[0].スロット.番号を返す(), 0);
}

#[test]
fn 版3のメッシュは全インデックスを塗る1件のプリミティブ列になる() {
    let 読み取り = 実行時形式からシーンを読む(&版3バイト列を作る()).unwrap();
    let 描画形状::通常メッシュ(メッシュ) = 読み取り.先頭の描画対象().形状() else {
        panic!("版3の静的シーンが通常メッシュとして読めなかった");
    };
    assert_eq!(メッシュ.プリミティブ列.len(), 1);
    assert_eq!(メッシュ.プリミティブ列[0].インデックス開始, 0);
    assert_eq!(メッシュ.プリミティブ列[0].インデックス数, 1);
    assert_eq!(メッシュ.プリミティブ列[0].頂点基準, 0);
    assert_eq!(メッシュ.プリミティブ列[0].材質スロット.番号を返す(), 0);
}

#[test]
fn 版3と最新版で先頭のヘッダー形式版が異なる() {
    let 版3 = 版3バイト列を作る();
    let 最新版 = crate::asset::シーンを実行時形式へ格納する(&静的シーンを作る(vec![10, 20, 30, 255], 0.2)).unwrap();
    assert_eq!(版3[8..12], アセット形式版::V3.番号().to_le_bytes());
    assert_eq!(最新版[8..12], アセット形式版::V4.番号().to_le_bytes());
}

#[test]
fn 版3は複数プリミティブのメッシュを表せない() {
    assert_eq!(
        super::write::内容を書く(&二材質シーンを作る()),
        Err(アセット実行時形式エラー::材質割当不正(
            材質割当エラー::旧版が表せないプリミティブ列 { プリミティブ数: 2 }
        ))
    );
}
