//! 版1メッシュ要素の固定バイト長を所有する。読み取り時の件数境界検査と、ストリーミングのメモリ見積が同じ数字を根拠にするため、
//! 形式を変えたときに見積だけ古い数字のまま残ることが起こらない。
//! 参照: `_doc/設計/アセット実行時形式.md`

/// 位置3成分、法線3成分、接線4成分、UV2成分の各f32で48バイトになる。
pub(crate) const 頂点長: usize = 48;

/// インデックスはu32である。
pub(crate) const インデックス長: usize = 4;

/// ジョイント添字4個のu16とウェイト4成分のf32で24バイトになる。
pub(super) const スキン頂点属性長: usize = 24;

/// 個体配置1件の実行時形式でのバイト数。平行移動3成分、回転4成分、スケール3成分の各f32で40バイトになる。
pub(crate) const 個体配置長: usize = 40;

/// 個体1件のために描画側がホストメモリへ持つ検査記録のバイト数。同一パスの区間の中で同じ個体IDが重複しないことの検査が
/// 個体ごとに「最後に見た検査の世代番号」をu32で1つ持つため4バイトになる。記録は束の読込時に個体数ぶんを一度だけ確保し、
/// 束が常駐するあいだ保持される(参照: `crates/blitz_render/src/renderer/scene_draw_resources/render_object_resources/seen_record.rs`、
/// 区間配置の検査は同ディレクトリの`visible_id_content.rs`が持つ)。
/// 実確保はレンダラーの内側にあり見積からは観測できないため、要素1件ぶんの長さを安全側の定数としてここが持つ。
/// これを数えないと、個体数の多いチャンクほど系統的に過小な見積で収容を決めることになる。
pub(crate) const 個体別置換検査記録長: usize = 4;

/// 個体1件がGPUで占める変換のバイト数。列優先4x4のf32と、列がf32の4成分に整列した3x3の法線行列で112バイトになる。
/// 注意: この値はblitz_renderの個体変換の配置と一致していなければならない。見積だけが古い数字のまま残ることを避けるため、
/// 形式を変えるときは両方を同時に直す。
pub(crate) const 個体変換長: usize = 112;

/// 個体1件がGPUで占める可視ID列のバイト数。1件はu32の4バイトであり、1個体はシーンの区間と帯0から帯3の区間へ
/// 最大5回現れるため1本の列で20バイト、フレームインフライト数2本ぶんを束の読込時に確保するため40バイトになる。
/// 個体変換と別の定数にするのは、置き場が違う(個体変換はデバイスローカル、可視ID列はホスト可視)ためである。
/// 注意: この値はblitz_renderの`可視IDバイト長`と`可視ID列を読むパス数`と`フレームインフライト数`の積と一致していなければならない。
/// 片方だけを変えると見積が実確保から離れる。
/// 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の帯別区間(4区分並べの後継)」
///
/// 個体が1体だけの描画対象は専用バッファを持たず、束が1つだけ持つ共有列を読む。その対象をこの長さで数えるのは
/// 実確保を上回る安全側の概算である。逆に束の共有列そのもの(束あたり40バイト)は見積に含めない。個体数に比例せず、
/// 物量を上げても増えない束あたりの定数だからである。
pub(crate) const 個体別可視ID列長: usize = 40;

/// 個体1件のためにコンポジションルートが毎フレームの選択に使うホストメモリのバイト数。可視ID列の写しを1本持ち、
/// 1個体が最大5回現れるためu32の5件で20バイトになる。GPUの可視ID列と違いフレームインフライトぶんの二重化は無く、
/// 1本を毎フレーム使い回す(参照: `crates/blitz_engine/src/visibility/stage_tray.rs`)。
/// 実確保はコンポジションルートが持つ受け皿の中にあり見積からは観測できないため、要素1件ぶんの長さを安全側の定数としてここが持つ。
pub(crate) const 個体別選択ID列長: usize = 20;
