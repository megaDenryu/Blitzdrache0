//! 版4のプリミティブ列を書く工程と、旧版が表せる形かの判定。受け取るのはメッシュ、書くのは件数とプリミティブ1件ずつである。
//! 触れるのは`プリミティブ列`とその参照先のインデックス一覧だけであり、「区間はインデックス一覧に収まり、頂点基準を加えたインデックスは頂点数に収まる」という不変条件をこの工程が守る。

use super::super::super::{アセット実行時形式エラー, 材質割当エラー};
use super::super::bytes::書込先;
use crate::asset::mesh_data::メッシュデータ;
use crate::asset::mesh_primitive::メッシュプリミティブ;

pub(super) fn 書く(出力: &mut 書込先, メッシュ: &メッシュデータ) -> Result<(), アセット実行時形式エラー> {
    if メッシュ.プリミティブ列.is_empty() {
        return Err(材質割当エラー::プリミティブなし.into());
    }
    出力.件数(メッシュ.プリミティブ列.len())?;
    for プリミティブ in &メッシュ.プリミティブ列 {
        区間を検査する(プリミティブ, メッシュ)?;
        出力.件数(プリミティブ.インデックス開始)?;
        出力.件数(プリミティブ.インデックス数)?;
        出力.u32(プリミティブ.頂点基準);
        出力.u32(プリミティブ.材質スロット.番号を返す());
    }
    Ok(())
}

/// 全インデックスを材質スロット0の1件で塗るプリミティブ列だけを版1から版3は表せる。
/// 表せない列を無言で切り捨てると、読み戻したときに材質境界が消えたことに気づけない。
#[cfg(test)]
pub(super) fn 旧版が表せるかを検査する(メッシュ: &メッシュデータ) -> Result<(), アセット実行時形式エラー> {
    let 全体を塗る単一プリミティブ = メッシュ.プリミティブ列.len() == 1
        && メッシュ.プリミティブ列.iter().all(|プリミティブ| {
            プリミティブ.インデックス開始 == 0
                && プリミティブ.インデックス数 == メッシュ.インデックス一覧.len()
                && プリミティブ.頂点基準 == 0
                && プリミティブ.材質スロット.番号を返す() == 0
        });
    if 全体を塗る単一プリミティブ {
        return Ok(());
    }
    Err(材質割当エラー::旧版が表せないプリミティブ列 {
        プリミティブ数: メッシュ.プリミティブ列.len(),
    }
    .into())
}

fn 区間を検査する(
    プリミティブ: &メッシュプリミティブ, メッシュ: &メッシュデータ
) -> Result<(), アセット実行時形式エラー> {
    if プリミティブ.インデックス数 == 0 {
        return Err(材質割当エラー::空のプリミティブ.into());
    }
    let 終端 = プリミティブ
        .インデックス開始
        .checked_add(プリミティブ.インデックス数)
        .ok_or(アセット実行時形式エラー::長さ表現不能)?;
    let Some(区間) = メッシュ.インデックス一覧.get(プリミティブ.インデックス開始..終端) else {
        return Err(材質割当エラー::区間範囲外 {
            開始: プリミティブ.インデックス開始,
            件数: プリミティブ.インデックス数,
            インデックス数: メッシュ.インデックス一覧.len(),
        }
        .into());
    };
    for &インデックス in 区間 {
        let 頂点番号 = プリミティブ
            .頂点基準
            .checked_add(インデックス)
            .ok_or(アセット実行時形式エラー::長さ表現不能)?;
        if usize::try_from(頂点番号).map_or(true, |値| 値 >= メッシュ.頂点一覧.len()) {
            return Err(材質割当エラー::頂点範囲外 {
                頂点番号,
                頂点数: メッシュ.頂点一覧.len(),
            }
            .into());
        }
    }
    Ok(())
}
