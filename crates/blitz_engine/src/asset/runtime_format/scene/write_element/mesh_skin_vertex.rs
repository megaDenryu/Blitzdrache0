//! メッシュに任意で付くスキン頂点属性の並びを書く工程。受け取るのはメッシュとスキンのジョイント数、書くのは有無の判別値と属性列である。
//! 触れるのは`スキン頂点属性一覧`だけであり、「属性数は頂点数と一致し、ジョイント添字はスキンのジョイント数の範囲に収まる」という不変条件をこの工程が守る。

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::書込先;
use crate::asset::{mesh_data::メッシュデータ, skin_vertex_attribute::スキン頂点属性};

pub(super) fn 書く(
    出力: &mut 書込先, メッシュ: &メッシュデータ, ジョイント数: Option<usize>
) -> Result<(), アセット実行時形式エラー> {
    let Some(属性一覧) = &メッシュ.スキン頂点属性一覧 else {
        出力.u8(0);
        return Ok(());
    };
    let Some(ジョイント数) = ジョイント数 else {
        return Err(アセット実行時形式エラー::スキンなし頂点属性);
    };
    if 属性一覧.len() != メッシュ.頂点一覧.len() {
        return Err(アセット実行時形式エラー::スキン頂点属性数不一致 {
            属性数: 属性一覧.len(),
            頂点数: メッシュ.頂点一覧.len(),
        });
    }
    出力.u8(1);
    出力.件数(属性一覧.len())?;
    for 属性 in 属性一覧 {
        属性を書く(出力, 属性, ジョイント数)?;
    }
    Ok(())
}

fn 属性を書く(
    出力: &mut 書込先, 属性: &スキン頂点属性, ジョイント数: usize
) -> Result<(), アセット実行時形式エラー> {
    for &添字 in &属性.ジョイント {
        if usize::from(添字) >= ジョイント数 {
            return Err(アセット実行時形式エラー::スキンジョイント範囲外 {
                ジョイント添字: 添字,
                ジョイント数,
            });
        }
        出力.u16(添字);
    }
    for &ウェイト in &属性.ウェイト {
        出力.f32(ウェイト)?;
    }
    Ok(())
}
