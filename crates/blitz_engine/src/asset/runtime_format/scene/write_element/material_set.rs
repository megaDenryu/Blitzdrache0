//! 版4以降の材質集合を書く工程。受け取るのは材質集合と版ごとの要素の書き方、書くのは件数とスロットID順に並んだ材質1件ずつである。
//! テクスチャの並びと材質の種別の枝だけが版で変わるため、その2つの書き方を引数で受け取り、材質集合の並びはここが1つだけ持つ。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「材質特徴集合の初期確定」

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::書込先;
use super::version_codec::版ごとの要素の書き方;
use crate::asset::material_set::材質集合;

pub(in crate::asset::runtime_format::scene) fn 書く(
    出力: &mut 書込先,
    材質集合: &材質集合,
    書き方: 版ごとの要素の書き方,
) -> Result<(), アセット実行時形式エラー> {
    出力.件数(材質集合.件数())?;
    for 割当 in 材質集合.割当一覧() {
        出力.u32(割当.スロット.番号を返す());
        (書き方.材質1件())(出力, &割当.マテリアル, 書き方.テクスチャ1件())?;
    }
    Ok(())
}
