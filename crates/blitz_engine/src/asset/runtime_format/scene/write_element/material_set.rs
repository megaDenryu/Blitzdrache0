//! 版4と版5の材質集合を書く工程。受け取るのは材質集合とテクスチャ1件を書く工程、書くのは件数とスロットID順に並んだ材質1件ずつである。
//! テクスチャの並びだけが版で変わるため、その1件を書く工程を引数で受け取り、材質集合の並びはここが1つだけ持つ。
//! 材質特徴集合はテクスチャのOption列からの導出だけを正本にするため、書き手が値を指定する経路を持たない。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「材質特徴集合の初期確定」

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::書込先;
use super::material_element::{係数を書く, 金属粗さPBRの種別番号};
use super::texture::テクスチャを書く工程;
use crate::asset::material_data::マテリアルデータ;
use crate::asset::material_set::材質集合;
use crate::asset::pbr_material_data::金属粗さPBRデータ;

pub(in crate::asset::runtime_format::scene) fn 書く(
    出力: &mut 書込先,
    材質集合: &材質集合,
    テクスチャを書く: テクスチャを書く工程,
) -> Result<(), アセット実行時形式エラー> {
    出力.件数(材質集合.件数())?;
    for 割当 in 材質集合.割当一覧() {
        出力.u32(割当.スロット.番号を返す());
        let マテリアルデータ::金属粗さPBR(値) = &割当.マテリアル;
        材質を書く(出力, 値, テクスチャを書く)?;
    }
    Ok(())
}

fn 材質を書く(
    出力: &mut 書込先,
    値: &金属粗さPBRデータ,
    テクスチャを書く: テクスチャを書く工程,
) -> Result<(), アセット実行時形式エラー> {
    出力.u32(金属粗さPBRの種別番号);
    出力.u32(値.特徴集合().生値());
    テクスチャを書く(出力, 値.ベースカラー.as_ref())?;
    テクスチャを書く(出力, 値.金属粗さ.as_ref())?;
    テクスチャを書く(出力, 値.法線マップ.as_ref())?;
    for 成分 in 値.ベースカラー係数 {
        係数を書く(出力, 成分)?;
    }
    係数を書く(出力, 値.金属度係数)?;
    係数を書く(出力, 値.粗さ係数)
}
