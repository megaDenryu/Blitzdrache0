//! メッシュの頂点一覧・インデックス一覧を検査して書き、版ごとのプリミティブ列の有無を吸収する。
//! 版1から版3はプリミティブ列を持たないため、旧版が表せる形かを先に確かめてから頂点とインデックスだけを書く。

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::書込先;
use super::{mesh_primitive, mesh_skin_vertex};
use crate::asset::{mesh_data::メッシュデータ, vertex_attribute::メッシュ頂点属性};

/// 版1から版3のメッシュを書く。旧版で書き出す経路は検査だけが持つ。
#[cfg(test)]
pub(in crate::asset::runtime_format::scene) fn 旧版を書く(
    出力: &mut 書込先,
    メッシュ: &メッシュデータ,
    ジョイント数: Option<usize>,
) -> Result<(), アセット実行時形式エラー> {
    基本内容を検査する(メッシュ)?;
    mesh_primitive::旧版が表せるかを検査する(メッシュ)?;
    頂点とインデックスを書く(出力, メッシュ)?;
    mesh_skin_vertex::書く(出力, メッシュ, ジョイント数)
}

/// 版4のメッシュを書く。プリミティブ列はインデックス一覧の後、スキン頂点属性の前に並ぶ。
pub(in crate::asset::runtime_format::scene) fn 書く(
    出力: &mut 書込先,
    メッシュ: &メッシュデータ,
    ジョイント数: Option<usize>,
) -> Result<(), アセット実行時形式エラー> {
    基本内容を検査する(メッシュ)?;
    頂点とインデックスを書く(出力, メッシュ)?;
    mesh_primitive::書く(出力, メッシュ)?;
    mesh_skin_vertex::書く(出力, メッシュ, ジョイント数)
}

fn 頂点とインデックスを書く(
    出力: &mut 書込先, メッシュ: &メッシュデータ
) -> Result<(), アセット実行時形式エラー> {
    出力.件数(メッシュ.頂点一覧.len())?;
    for 頂点 in &メッシュ.頂点一覧 {
        頂点を書く(出力, 頂点)?;
    }
    出力.件数(メッシュ.インデックス一覧.len())?;
    for &添字 in &メッシュ.インデックス一覧 {
        出力.u32(添字);
    }
    Ok(())
}

fn 基本内容を検査する(メッシュ: &メッシュデータ) -> Result<(), アセット実行時形式エラー> {
    if メッシュ.頂点一覧.is_empty() {
        return Err(アセット実行時形式エラー::頂点なし);
    }
    if メッシュ.インデックス一覧.is_empty() {
        return Err(アセット実行時形式エラー::インデックスなし);
    }
    for &インデックス in &メッシュ.インデックス一覧 {
        if usize::try_from(インデックス).map_or(true, |値| 値 >= メッシュ.頂点一覧.len()) {
            return Err(アセット実行時形式エラー::インデックス範囲外 {
                インデックス,
                頂点数: メッシュ.頂点一覧.len(),
            });
        }
    }
    Ok(())
}

fn 頂点を書く(出力: &mut 書込先, 頂点: &メッシュ頂点属性) -> Result<(), アセット実行時形式エラー> {
    for 値 in 頂点.位置.into_iter().chain(頂点.法線).chain(頂点.接線).chain(頂点.uv) {
        出力.f32(値)?;
    }
    Ok(())
}
