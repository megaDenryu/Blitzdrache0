//! 材質1件を種別番号つきで書く工程と、その工程を版ごとに指す型。担当するのは、「その版が表せない種別を
//! 無言で切り捨てない」ことである。
//!
//! 版5までの書き手が地表の層の重ね合わせを型付きの失敗にするのは、その版の並びに種別2の場所が無いためである。
//! 先頭の層だけの絵へ縮退させると、旧い版で焼いた世界の塗り分けが黙って消える。

use super::super::super::アセット実行時形式エラー;
#[cfg(test)]
use super::super::super::材質割当エラー;
use super::super::bytes::書込先;
use super::material_element::{地表の層の重ね合わせの種別番号, 金属粗さPBRの種別番号};
use super::texture::テクスチャを書く工程;
use super::{pbr_material_body, surface_layer_body};
use crate::asset::material_data::マテリアルデータ;

/// 材質1件を書く工程の署名。版ごとの要素の書き方が、自分の版が表せる種別だけを書く工程をこの形で持つ。
pub(super) type 材質1件を書く工程 = fn(&mut 書込先, &マテリアルデータ, テクスチャを書く工程) -> Result<(), アセット実行時形式エラー>;

/// 版4と版5の材質1件。金属粗さPBRだけを表せる。版4と版5で書き出す経路は検査だけが持つ。
#[cfg(test)]
pub(super) fn 版5までの材質1件を書く(
    出力: &mut 書込先,
    マテリアル: &マテリアルデータ,
    テクスチャを書く: テクスチャを書く工程,
) -> Result<(), アセット実行時形式エラー> {
    match マテリアル {
        マテリアルデータ::金属粗さPBR(値) => {
            出力.u32(金属粗さPBRの種別番号);
            pbr_material_body::書く(出力, 値, テクスチャを書く)
        }
        マテリアルデータ::地表の層の重ね合わせ(_) => Err(材質割当エラー::旧版が表せない地表の層の重ね合わせ.into()),
    }
}

pub(super) fn 版6の材質1件を書く(
    出力: &mut 書込先,
    マテリアル: &マテリアルデータ,
    テクスチャを書く: テクスチャを書く工程,
) -> Result<(), アセット実行時形式エラー> {
    match マテリアル {
        マテリアルデータ::金属粗さPBR(値) => {
            出力.u32(金属粗さPBRの種別番号);
            pbr_material_body::書く(出力, 値, テクスチャを書く)
        }
        マテリアルデータ::地表の層の重ね合わせ(値) => {
            出力.u32(地表の層の重ね合わせの種別番号);
            surface_layer_body::書く(出力, 値, テクスチャを書く)
        }
    }
}
