//! 種別番号の後に続く、地表の層の重ね合わせの本体を書く工程。読み取り側の`read_element::surface_layer_body`と
//! 対になっており、片方だけを変えると往復が壊れる。
//!
//! 重みテクスチャを`Some`で渡すのは、この枝が重みを必ず持つためである。テクスチャ1件の並びを共有することで、
//! 有無の判別値と寸法と縮小段の綴りを地表の層のために書き直さずに済む。

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::書込先;
use super::material_element::係数を書く;
use super::texture::テクスチャを書く工程;
use crate::asset::material_data::地表の層の重ね合わせデータ;

pub(super) fn 書く(
    出力: &mut 書込先,
    値: &地表の層の重ね合わせデータ,
    テクスチャを書く: テクスチャを書く工程,
) -> Result<(), アセット実行時形式エラー> {
    テクスチャを書く(出力, Some(値.重みテクスチャ()))?;
    for 倍率 in 値.層ごとのタイル倍率() {
        出力.f32(倍率)?;
    }
    係数を書く(出力, 値.金属度係数())?;
    係数を書く(出力, 値.粗さ係数())
}
