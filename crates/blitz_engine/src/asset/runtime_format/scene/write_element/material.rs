//! 材質スロット0の単一材質を、金属粗さPBRとRGBA8テクスチャの並びで書く。
//! 材質集合を受け取って1件だけを書くのは、複数材質を表せない版がそれを無言で切り捨てないためである。

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::書込先;
use crate::asset::material_data::マテリアルデータ;
use crate::asset::material_set::材質集合;
use crate::asset::material_slot_id::材質スロットID;
use crate::asset::texture_data::テクスチャデータ;

/// 単一材質を表す材質集合が持つ唯一のスロット番号。
const 単一材質のスロット番号: u32 = 0;

pub(in crate::asset::runtime_format::scene) fn 書く(
    出力: &mut 書込先, 材質集合: &材質集合
) -> Result<(), アセット実行時形式エラー> {
    let 表せる = 材質集合.件数() == 1 && 材質集合.材質を参照する(材質スロットID::生成する(単一材質のスロット番号)).is_some();
    if !表せる {
        return Err(アセット実行時形式エラー::材質集合を表せない版 {
            材質数: 材質集合.件数()
        });
    }
    単一材質を書く(出力, 材質集合.先頭の材質())
}

fn 単一材質を書く(出力: &mut 書込先, マテリアル: &マテリアルデータ) -> Result<(), アセット実行時形式エラー> {
    match マテリアル {
        マテリアルデータ::金属粗さPBR(値) => {
            出力.u32(1);
            テクスチャを書く(出力, 値.ベースカラー.as_ref())?;
            テクスチャを書く(出力, 値.金属粗さ.as_ref())?;
            テクスチャを書く(出力, 値.法線マップ.as_ref())?;
            for 値 in 値.ベースカラー係数 {
                係数を書く(出力, 値)?;
            }
            係数を書く(出力, 値.金属度係数)?;
            係数を書く(出力, 値.粗さ係数)
        }
    }
}

fn 係数を書く(出力: &mut 書込先, 値: f32) -> Result<(), アセット実行時形式エラー> {
    if !(0.0..=1.0).contains(&値) {
        return Err(アセット実行時形式エラー::マテリアル係数範囲外);
    }
    出力.f32(値)
}

fn テクスチャを書く(
    出力: &mut 書込先, テクスチャ: Option<&テクスチャデータ>
) -> Result<(), アセット実行時形式エラー> {
    let Some(値) = テクスチャ else {
        出力.u8(0);
        return Ok(());
    };
    if 値.幅 == 0 || 値.高さ == 0 {
        return Err(アセット実行時形式エラー::テクスチャ寸法ゼロ);
    }
    let 期待長 = u64::from(値.幅)
        .checked_mul(u64::from(値.高さ))
        .and_then(|画素数| 画素数.checked_mul(4))
        .ok_or(アセット実行時形式エラー::長さ表現不能)?;
    let 実長 = u64::try_from(値.rgba8.len()).map_err(|_| アセット実行時形式エラー::長さ表現不能)?;
    if 期待長 != 実長 {
        return Err(アセット実行時形式エラー::テクスチャ長不一致 { 期待長, 実長 });
    }
    出力.u8(1);
    出力.u32(値.幅);
    出力.u32(値.高さ);
    出力.u64(実長);
    出力.バイト列(&値.rgba8);
    Ok(())
}
