//! 版1から版3の材質1件を書く。材質特徴集合を持たない並びであり、材質スロット0の単一材質しか表せない。
//! 材質集合を受け取って1件だけを書くのは、複数材質を表せない版がそれを無言で切り捨てないためである。

use super::super::super::{アセット実行時形式エラー, 材質割当エラー};
use super::super::bytes::書込先;
use super::material_element::{テクスチャを書く, 係数を書く, 金属粗さPBRの種別番号};
use crate::asset::material_data::マテリアルデータ;
use crate::asset::material_set::材質集合;
use crate::asset::material_slot_id::材質スロットID;

/// 単一材質を表す材質集合が持つ唯一のスロット番号。
const 単一材質のスロット番号: u32 = 0;

pub(in crate::asset::runtime_format::scene) fn 書く(
    出力: &mut 書込先, 材質集合: &材質集合
) -> Result<(), アセット実行時形式エラー> {
    let スロット0を指す = 材質集合.材質を参照する(材質スロットID::生成する(単一材質のスロット番号)).is_some();
    let Some(マテリアル) = 材質集合.唯一の材質().filter(|_| スロット0を指す) else {
        return Err(材質割当エラー::旧版が表せない材質集合 {
            材質数: 材質集合.件数()
        }
        .into());
    };
    let マテリアルデータ::金属粗さPBR(値) = マテリアル;
    出力.u32(金属粗さPBRの種別番号);
    テクスチャを書く(出力, 値.ベースカラー.as_ref())?;
    テクスチャを書く(出力, 値.金属粗さ.as_ref())?;
    テクスチャを書く(出力, 値.法線マップ.as_ref())?;
    for 成分 in 値.ベースカラー係数 {
        係数を書く(出力, 成分)?;
    }
    係数を書く(出力, 値.金属度係数)?;
    係数を書く(出力, 値.粗さ係数)
}
