//! テクスチャ1件を書く工程。受け取るのは書込先と有無つきの格納済みテクスチャ、書くのは版ごとの並びである。
//! 読み取り側の`read_element::texture`と対になっており、片方だけを変えると往復が壊れるため、並びを決める箇所を版ごとに2つへ散らさない。
//! 版4までの並びはRGBA8の原寸1枚しか表せないため、ブロック圧縮の値を渡されたら型付きエラーで拒む。
//! 参照: `_doc/設計/アセット実行時形式.md`「シーン内容の版5」

use super::super::super::アセット実行時形式エラー;
#[cfg(test)]
use super::super::super::材質割当エラー;
use super::super::bytes::書込先;
use super::super::texture_format_tag::格納形式の判別値を返す;
use crate::asset::texture_storage::格納済みテクスチャ;

/// テクスチャ1件を書く工程の署名。版ごとの組み立てが、自分の版の並びを書く工程をこの形で受け取る。
pub(in crate::asset::runtime_format::scene) type テクスチャを書く工程 =
    fn(&mut 書込先, Option<&格納済みテクスチャ>) -> Result<(), アセット実行時形式エラー>;

/// 版4までの並びで書き出す経路は検査だけが持つ。実行時形式の書き出しは常に最新版で行うためである。
#[cfg(test)]
pub(in crate::asset::runtime_format::scene) fn 版4までのテクスチャを書く(
    出力: &mut 書込先,
    テクスチャ: Option<&格納済みテクスチャ>,
) -> Result<(), アセット実行時形式エラー> {
    let Some(値) = テクスチャ else {
        出力.u8(0);
        return Ok(());
    };
    let Some(画素列) = 値.rgba8の原寸の画素列を返す() else {
        return Err(材質割当エラー::旧版が表せないテクスチャ格納形式.into());
    };
    let 長さ = u64::try_from(画素列.len()).map_err(|_| アセット実行時形式エラー::長さ表現不能)?;
    有無と寸法を書く(出力, 値);
    出力.u64(長さ);
    出力.バイト列(画素列);
    Ok(())
}

pub(in crate::asset::runtime_format::scene) fn 版5のテクスチャを書く(
    出力: &mut 書込先,
    テクスチャ: Option<&格納済みテクスチャ>,
) -> Result<(), アセット実行時形式エラー> {
    let Some(値) = テクスチャ else {
        出力.u8(0);
        return Ok(());
    };
    有無と寸法を書く(出力, 値);
    出力.u8(格納形式の判別値を返す(値.格納形式を返す()));
    出力.件数(値.段ごとのバイト列を返す().len())?;
    for 段 in 値.段ごとのバイト列を返す() {
        let 長さ = u64::try_from(段.len()).map_err(|_| アセット実行時形式エラー::長さ表現不能)?;
        出力.u64(長さ);
        出力.バイト列(段);
    }
    Ok(())
}

/// 寸法の1以上は`格納済みテクスチャ`の生成が保証するため、書く側は検査を繰り返さない。
fn 有無と寸法を書く(出力: &mut 書込先, 値: &格納済みテクスチャ) {
    出力.u8(1);
    出力.u32(値.幅を返す());
    出力.u32(値.高さを返す());
}
