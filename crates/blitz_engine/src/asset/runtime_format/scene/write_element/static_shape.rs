//! 静的物理形状の節の書き込み。読み取り側の`read_element::static_shape`と対になっており、片方だけを変えると往復が壊れる。
//!
//! 版6までの書き方が、形状を持つシーンを型付きエラーで拒むのは、その並びが節を持たず、黙って書けば焼いた形状が消えるためである。
//! 形状を持たないシーンは版6でも版7でも同じ並びになるため、版6の書き方でそのまま通る。
//! 参照: `_doc/設計/アセット実行時形式.md`「シーン内容の版7」

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::書込先;
#[cfg(test)]
use crate::static_shape::静的物理形状エラー;
use crate::static_shape::{チャンクの静的物理形状, 衝突対象の子形状, 静的な衝突対象};

pub(in crate::asset::runtime_format::scene) type 静的物理形状の節を書く工程 =
    fn(&mut 書込先, &チャンクの静的物理形状) -> Result<(), アセット実行時形式エラー>;

#[cfg(test)]
pub(in crate::asset::runtime_format::scene) fn 版6までの静的物理形状を書く(
    _出力: &mut 書込先,
    形状: &チャンクの静的物理形状,
) -> Result<(), アセット実行時形式エラー> {
    if 形状.衝突対象数() == 0 {
        return Ok(());
    }
    Err(静的物理形状エラー::節を持たない旧版で焼こうとした.into())
}

pub(in crate::asset::runtime_format::scene) fn 版7の静的物理形状を書く(
    出力: &mut 書込先,
    形状: &チャンクの静的物理形状,
) -> Result<(), アセット実行時形式エラー> {
    出力.件数(形状.衝突対象数())?;
    for 対象 in 形状.衝突対象一覧() {
        衝突対象を書く(出力, 対象)?;
    }
    Ok(())
}

fn 衝突対象を書く(出力: &mut 書込先, 対象: &静的な衝突対象) -> Result<(), アセット実行時形式エラー> {
    let 綴り = 対象.安定識別子().綴り().as_bytes();
    出力.件数(綴り.len())?;
    出力.バイト列(綴り);
    出力.件数(対象.子形状一覧().len())?;
    for 子形状 in 対象.子形状一覧() {
        子形状を書く(出力, 子形状)?;
    }
    Ok(())
}

fn 子形状を書く(出力: &mut 書込先, 子形状: &衝突対象の子形状) -> Result<(), アセット実行時形式エラー> {
    出力.u32(子形状.識別子().番号を返す());
    let 直方体 = 子形状.直方体();
    let 中心 = 直方体.中心();
    出力.f32(中心.x().値())?;
    出力.f32(中心.y().値())?;
    出力.f32(中心.z().値())?;
    let 回転 = 直方体.回転().境界用xyzw配列();
    for 成分 in 回転 {
        出力.f32(成分)?;
    }
    let 半分の長さ = 直方体.軸ごとの半分の長さ();
    出力.f32(半分の長さ.x().値())?;
    出力.f32(半分の長さ.y().値())?;
    出力.f32(半分の長さ.z().値())
}
