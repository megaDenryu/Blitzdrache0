//! 版2のシーン。描画対象が形状の判別値を持ち、1つの通常メッシュか、段番号順の地形LODメッシュ群かを選べる。
//! これが最新版であるため、読み取り結果は変換を挟まずそのまま`シーンデータ`である。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「地形の表現」

mod read;
mod write;

use super::super::{アセット実行時形式エラー, アセット形式版, 実行時アセットを格納する, 実行時アセット種別};
use crate::asset::scene_data::シーンデータ;

pub(super) use read::内容を読む;

/// 形状の判別値。読み取りと書き込みが同じ値を使うため、対応をこの2つの定数が持つ。
pub(super) const 通常メッシュの判別値: u8 = 0;
pub(super) const 地形LODメッシュ群の判別値: u8 = 1;

