//! 描画対象の形状が参照する材質スロットIDが、その描画対象の材質集合に実在するかを確かめる工程。
//! 受け取るのは形状と材質集合、返すのは可否である。読み書きの両方が同じ判定を通るため、焼く側と読む側で受理する範囲がずれない。
//! LOD段ごとにプリミティブ数が違ってもよいが、参照するスロットは原型のスロット集合の内側でなければならない。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「入力契約と実行時形式(scene v4)」

use super::super::super::{アセット実行時形式エラー, 材質割当エラー};
use crate::asset::draw_shape::描画形状;
use crate::asset::material_set::材質集合;

pub(super) fn 検査する(形状: &描画形状, 材質集合: &材質集合) -> Result<(), アセット実行時形式エラー> {
    for メッシュ in 形状.全メッシュ() {
        for プリミティブ in &メッシュ.プリミティブ列 {
            if 材質集合.材質を参照する(プリミティブ.材質スロット).is_none() {
                return Err(材質割当エラー::材質スロット未定義 {
                    番号: プリミティブ.材質スロット.番号を返す(),
                }
                .into());
            }
        }
    }
    Ok(())
}
