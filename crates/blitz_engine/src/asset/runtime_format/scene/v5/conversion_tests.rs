//! 版5で焼かれたシーンが最新版の型へ変換されて読めることの検査。版5の書き出しは検査だけが持つため、材料もここで作る。
//! 版5から版6への昇格が恒等であること、つまり版5の内容のバイト列が版6の内容のバイト列と一致することをここで固定する。
//! 最新版との違いは、共通ヘッダーの形式版と、版7が末尾へ足した静的物理形状の節だけである。
//!
//! 版5が地表の層の重ね合わせを表せないことも見る。表せない材質を先頭の層だけの絵へ縮退させず型付きで拒む枝である。

#![allow(clippy::unwrap_used)]

use super::super::super::{アセット形式版, 実行時アセットを格納する, 実行時アセット種別};
use super::super::surface_layer_fixture::地表の層の重ね合わせの静的シーンを作る;
use crate::asset::runtime_format::実行時形式からシーンを読む;
use crate::asset::runtime_scene_tests::静的シーンを作る;
use crate::asset::材質割当エラー;

fn 材料のシーン() -> crate::asset::シーンデータ {
    静的シーンを作る(vec![10, 20, 30, 255], 0.2)
}

fn 版5バイト列を作る() -> Vec<u8> {
    let 内容 = super::シーン内容を書く(&材料のシーン()).unwrap();
    実行時アセットを格納する(アセット形式版::V5, 実行時アセット種別::シーン, &内容).unwrap()
}

#[test]
fn 版5のシーンを最新版へ変換して読む() {
    assert_eq!(実行時形式からシーンを読む(&版5バイト列を作る()).unwrap(), 材料のシーン());
}

#[test]
fn 版5と最新版の違いは形式版と静的物理形状の節だけである() {
    let 版5 = 版5バイト列を作る();
    let 最新版 = crate::asset::シーンを実行時形式へ格納する(&材料のシーン()).unwrap();
    assert_eq!(版5[8..12], アセット形式版::V5.番号().to_le_bytes());
    assert_eq!(最新版[8..12], アセット形式版::V7.番号().to_le_bytes());
    assert_eq!(版5[..8], 最新版[..8]);
    // 版7が足すのは末尾の「衝突対象0件」を表す4バイトだけであり、その手前は内容長の宣言を除いて1バイトも変わらない。
    assert_eq!(版5[24..], 最新版[24..最新版.len() - 4]);
}

#[test]
fn 版5は地表の層の重ね合わせを表せない() {
    let シーン = 地表の層の重ね合わせの静的シーンを作る();
    assert_eq!(
        super::シーン内容を書く(&シーン),
        Err(材質割当エラー::旧版が表せない地表の層の重ね合わせ.into())
    );
    assert!(crate::asset::シーンを実行時形式へ格納する(&シーン).is_ok());
}
