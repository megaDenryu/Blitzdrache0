//! 静的物理形状の節の読み取り。版7が描画対象・スキン・アニメーションの後ろへ足した節であり、版6までは節そのものが無い。
//!
//! 版6までを「衝突対象0件」として読むのは既定値の無言の適用ではない。版6は建物の静的物理形状を焼かない時期の版であり、
//! その時期の生成物には静的な衝突対象が実際に1件も無いためである。カタログの版1が個体数を0として最新版へ変換するのと同じ論理である。
//! 参照: `_doc/設計/アセット実行時形式.md`「シーン内容の版7」

use blitz_math::{クォータニオン, メートル, ローカル, 位置};

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::読取位置;
use crate::static_shape::{
    チャンクの静的物理形状, 任意姿勢の直方体, 子形状識別子, 直方体の軸ごとの半分の長さ, 衝突対象の子形状, 衝突対象の安定識別子, 静的な衝突対象,
};

/// 子形状1件の最小バイト数。子形状識別子4 + 中心12 + 回転16 + 軸ごとの半分の長さ12 の合計である。
const 子形状長: usize = 44;

/// 衝突対象1件の最小バイト数。安定識別子の長さ4 + 子形状数4 + 子形状1件の合計である。
const 衝突対象最小長: usize = 4 + 4 + 子形状長;

pub(in crate::asset::runtime_format::scene) type 静的物理形状の節を読む工程 =
    fn(&mut 読取位置<'_>) -> Result<チャンクの静的物理形状, アセット実行時形式エラー>;

pub(in crate::asset::runtime_format::scene) fn 版6までの静的物理形状を読む(
    _入力: &mut 読取位置<'_>,
) -> Result<チャンクの静的物理形状, アセット実行時形式エラー> {
    Ok(チャンクの静的物理形状::空を作る())
}

pub(in crate::asset::runtime_format::scene) fn 版7の静的物理形状を読む(
    入力: &mut 読取位置<'_>,
) -> Result<チャンクの静的物理形状, アセット実行時形式エラー> {
    let 対象数 = 入力.件数(衝突対象最小長)?;
    let mut 衝突対象一覧 = Vec::with_capacity(対象数);
    for _ in 0..対象数 {
        衝突対象一覧.push(衝突対象を読む(入力)?);
    }
    Ok(チャンクの静的物理形状::衝突対象一覧から生成する(衝突対象一覧)?)
}

fn 衝突対象を読む(入力: &mut 読取位置<'_>) -> Result<静的な衝突対象, アセット実行時形式エラー> {
    let 綴りの長さ = 入力.usize()?;
    let 綴り = std::str::from_utf8(入力.バイト列(綴りの長さ)?).map_err(|_| アセット実行時形式エラー::不正な文字列)?;
    let 安定識別子 = 衝突対象の安定識別子::生成する(綴り)?;
    let 子形状数 = 入力.件数(子形状長)?;
    let mut 子形状一覧 = Vec::with_capacity(子形状数);
    for _ in 0..子形状数 {
        子形状一覧.push(子形状を読む(入力)?);
    }
    Ok(静的な衝突対象::安定識別子と子形状一覧から生成する(
        安定識別子,
        子形状一覧,
    )?)
}

fn 子形状を読む(入力: &mut 読取位置<'_>) -> Result<衝突対象の子形状, アセット実行時形式エラー> {
    let 識別子 = 子形状識別子::番号から生成する(入力.u32()?);
    let 中心 = 位置::生成する(
        メートル::生成する(入力.f32()?),
        メートル::生成する(入力.f32()?),
        メートル::生成する(入力.f32()?),
    );
    let 回転 = クォータニオン::<ローカル, ローカル>::生成する(入力.f32()?, 入力.f32()?, 入力.f32()?, 入力.f32()?)
        .map_err(|_| crate::static_shape::静的物理形状エラー::回転を正規化できない)?;
    let 半分の長さ = 直方体の軸ごとの半分の長さ::生成する([
        メートル::生成する(入力.f32()?),
        メートル::生成する(入力.f32()?),
        メートル::生成する(入力.f32()?),
    ])?;
    Ok(衝突対象の子形状::識別子と直方体から生成する(
        識別子,
        任意姿勢の直方体::生成する(中心, 回転, 半分の長さ)?,
    ))
}
