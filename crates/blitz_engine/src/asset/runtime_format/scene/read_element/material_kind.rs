//! 材質1件の種別番号を判別して本体の読み方を選ぶ工程と、その工程を版ごとに指す型。担当するのは、
//! 「その版がどの種別を表せるか」を版の側でなくここ1箇所で数え上げることである。
//!
//! 版4と版5が種別1だけを受け付けるのは、地表の層の重ね合わせを表せない並びだからである。未知の番号と同じ扱いで
//! 拒むのは、その版で焼かれたファイルに種別2が現れることが形式の破れだからである。

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::読取位置;
use super::material_element::{地表の層の重ね合わせの種別番号, 金属粗さPBRの種別番号};
use super::texture::テクスチャを読む工程;
use super::{pbr_material_body, surface_layer_body};
use crate::asset::material_data::マテリアルデータ;

/// 材質1件を読む工程の署名。版ごとの材質の並びの読み方が、自分の版が表せる種別だけを読む工程をこの形で持つ。
pub(super) type 材質1件を読む工程 =
    fn(&mut 読取位置<'_>, テクスチャを読む工程) -> Result<マテリアルデータ, アセット実行時形式エラー>;

/// 版4と版5の材質1件。金属粗さPBRだけを表せる。
pub(super) fn 版5までの材質1件を読む(
    入力: &mut 読取位置<'_>,
    テクスチャを読む: テクスチャを読む工程,
) -> Result<マテリアルデータ, アセット実行時形式エラー> {
    let 種別 = 入力.u32()?;
    if 種別 != 金属粗さPBRの種別番号 {
        return Err(アセット実行時形式エラー::未知のマテリアル種別(種別));
    }
    Ok(マテリアルデータ::金属粗さPBR(
        pbr_material_body::読む(入力, テクスチャを読む)?,
    ))
}

/// 版6の材質1件。金属粗さPBRと地表の層の重ね合わせの2つの種別を表せる。
pub(super) fn 版6の材質1件を読む(
    入力: &mut 読取位置<'_>,
    テクスチャを読む: テクスチャを読む工程,
) -> Result<マテリアルデータ, アセット実行時形式エラー> {
    let 種別 = 入力.u32()?;
    if 種別 == 金属粗さPBRの種別番号 {
        return Ok(マテリアルデータ::金属粗さPBR(
            pbr_material_body::読む(入力, テクスチャを読む)?,
        ));
    }
    if 種別 == 地表の層の重ね合わせの種別番号 {
        return Ok(マテリアルデータ::地表の層の重ね合わせ(surface_layer_body::読む(
            入力,
            テクスチャを読む,
        )?));
    }
    Err(アセット実行時形式エラー::未知のマテリアル種別(種別))
}
