//! 版4のプリミティブ列を読む工程。受け取るのは読取位置と読み終えたインデックス一覧と頂点数、返すのは非空のプリミティブ列である。
//! 区間がインデックス一覧に収まること、および頂点基準を加えたインデックスが頂点数に収まることをここで確かめる。

use super::super::super::{アセット実行時形式エラー, 材質割当エラー};
use super::super::bytes::読取位置;
use crate::asset::material_slot_id::材質スロットID;
use crate::asset::mesh_primitive::メッシュプリミティブ;

/// プリミティブ1件の実行時形式でのバイト数。インデックス開始・インデックス数・頂点基準・材質スロットIDの各u32で16バイトになる。
pub(super) const プリミティブ長: usize = 16;

pub(super) fn 読む(
    入力: &mut 読取位置<'_>,
    インデックス一覧: &[u32],
    頂点数: usize,
) -> Result<Vec<メッシュプリミティブ>, アセット実行時形式エラー> {
    let 件数 = 入力.件数(プリミティブ長)?;
    if 件数 == 0 {
        return Err(材質割当エラー::プリミティブなし.into());
    }
    let mut プリミティブ列 = Vec::with_capacity(件数);
    for _ in 0..件数 {
        let 開始 = usize::try_from(入力.u32()?).map_err(|_| アセット実行時形式エラー::長さ表現不能)?;
        let 数 = usize::try_from(入力.u32()?).map_err(|_| アセット実行時形式エラー::長さ表現不能)?;
        let プリミティブ = メッシュプリミティブ {
            インデックス開始: 開始,
            インデックス数: 数,
            頂点基準: 入力.u32()?,
            材質スロット: 材質スロットID::生成する(入力.u32()?),
        };
        区間を検査する(&プリミティブ, インデックス一覧, 頂点数)?;
        プリミティブ列.push(プリミティブ);
    }
    Ok(プリミティブ列)
}

fn 区間を検査する(
    プリミティブ: &メッシュプリミティブ,
    インデックス一覧: &[u32],
    頂点数: usize,
) -> Result<(), アセット実行時形式エラー> {
    if プリミティブ.インデックス数 == 0 {
        return Err(材質割当エラー::空のプリミティブ.into());
    }
    let 終端 = プリミティブ
        .インデックス開始
        .checked_add(プリミティブ.インデックス数)
        .ok_or(アセット実行時形式エラー::長さ表現不能)?;
    let Some(区間) = インデックス一覧.get(プリミティブ.インデックス開始..終端) else {
        return Err(材質割当エラー::区間範囲外 {
            開始: プリミティブ.インデックス開始,
            件数: プリミティブ.インデックス数,
            インデックス数: インデックス一覧.len(),
        }
        .into());
    };
    for &インデックス in 区間 {
        let 頂点番号 = プリミティブ
            .頂点基準
            .checked_add(インデックス)
            .ok_or(アセット実行時形式エラー::長さ表現不能)?;
        if usize::try_from(頂点番号).map_or(true, |値| 値 >= 頂点数) {
            return Err(材質割当エラー::頂点範囲外 { 頂点番号, 頂点数 }.into());
        }
    }
    Ok(())
}
