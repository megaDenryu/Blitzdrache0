//! メッシュの頂点一覧・インデックス一覧を検証して読み、版ごとのプリミティブ列の有無を吸収する。
//! 版1から版3はプリミティブ列を持たないため、全インデックスを材質スロット0で塗る1件のプリミティブ列へ変換して最新の型を作る。

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::読取位置;
use super::super::mesh_layout::{インデックス長, 頂点長};
use super::{mesh_primitive, mesh_skin_vertex};
use crate::asset::mesh_data::メッシュデータ;
use crate::asset::vertex_attribute::メッシュ頂点属性;

/// 版1から版3のメッシュを読み、単一プリミティブのメッシュへ変換する。
pub(in crate::asset::runtime_format::scene) fn 旧版を読む(
    入力: &mut 読取位置<'_>,
) -> Result<メッシュデータ, アセット実行時形式エラー> {
    let (頂点一覧, インデックス一覧) = 頂点とインデックスを読む(入力)?;
    let スキン頂点属性一覧 = mesh_skin_vertex::読む(入力, 頂点一覧.len())?;
    Ok(メッシュデータ::単一プリミティブで生成する(
        頂点一覧,
        インデックス一覧,
        スキン頂点属性一覧,
    ))
}

/// 版4のメッシュを読む。プリミティブ列はインデックス一覧の後、スキン頂点属性の前に並ぶ。
pub(in crate::asset::runtime_format::scene) fn 読む(
    入力: &mut 読取位置<'_>,
) -> Result<メッシュデータ, アセット実行時形式エラー> {
    let (頂点一覧, インデックス一覧) = 頂点とインデックスを読む(入力)?;
    let プリミティブ列 = mesh_primitive::読む(入力, &インデックス一覧, 頂点一覧.len())?;
    let スキン頂点属性一覧 = mesh_skin_vertex::読む(入力, 頂点一覧.len())?;
    Ok(メッシュデータ {
        頂点一覧,
        インデックス一覧,
        スキン頂点属性一覧,
        プリミティブ列,
    })
}

fn 頂点とインデックスを読む(
    入力: &mut 読取位置<'_>,
) -> Result<(Vec<メッシュ頂点属性>, Vec<u32>), アセット実行時形式エラー> {
    let 頂点数 = 入力.件数(頂点長)?;
    if 頂点数 == 0 {
        return Err(アセット実行時形式エラー::頂点なし);
    }
    let mut 頂点一覧 = Vec::with_capacity(頂点数);
    for _ in 0..頂点数 {
        頂点一覧.push(頂点を読む(入力)?);
    }
    let 添字数 = 入力.件数(インデックス長)?;
    if 添字数 == 0 {
        return Err(アセット実行時形式エラー::インデックスなし);
    }
    let mut インデックス一覧 = Vec::with_capacity(添字数);
    for _ in 0..添字数 {
        let インデックス = 入力.u32()?;
        if usize::try_from(インデックス).map_or(true, |値| 値 >= 頂点数) {
            return Err(アセット実行時形式エラー::インデックス範囲外 {
                インデックス, 頂点数
            });
        }
        インデックス一覧.push(インデックス);
    }
    Ok((頂点一覧, インデックス一覧))
}

fn 頂点を読む(入力: &mut 読取位置<'_>) -> Result<メッシュ頂点属性, アセット実行時形式エラー> {
    Ok(メッシュ頂点属性 {
        位置: [入力.f32()?, 入力.f32()?, 入力.f32()?],
        法線: [入力.f32()?, 入力.f32()?, 入力.f32()?],
        接線: [入力.f32()?, 入力.f32()?, 入力.f32()?, 入力.f32()?],
        uv: [入力.f32()?, 入力.f32()?],
    })
}
