//! 材質の中で版をまたいで変わらない要素を読む工程。担当するのは材質種別の番号と、0以上1以下の係数である。
//! 材質の版ごとの並びが共通して使うため、係数の範囲を確かめる場所を版の数だけ散らさない。
//! テクスチャ1件の並びは版で変わるため`read_element::texture`が持つ。

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::読取位置;

/// 金属粗さPBRを表す材質種別の番号。どの版でも同じ番号である。
pub(super) const 金属粗さPBRの種別番号: u32 = 1;

/// 地表の層の重ね合わせを表す材質種別の番号。版6から現れる。
/// 注意: 番号は焼いたファイルの中に残るため、既存の番号を付け替えてはならない。
pub(super) const 地表の層の重ね合わせの種別番号: u32 = 2;

pub(super) fn 係数を読む(入力: &mut 読取位置<'_>) -> Result<f32, アセット実行時形式エラー> {
    let 値 = 入力.f32()?;
    if (0.0..=1.0).contains(&値) {
        Ok(値)
    } else {
        Err(アセット実行時形式エラー::マテリアル係数範囲外)
    }
}
