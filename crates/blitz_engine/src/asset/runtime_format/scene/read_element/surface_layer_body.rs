//! 種別番号の後に続く、地表の層の重ね合わせの本体を読む工程。受け取るのは読取位置とテクスチャ1件を読む工程、
//! 返すのは検証済みの地表の層の重ね合わせデータである。
//!
//! 重みテクスチャの有無の判別値が「無し」だった場合を型付きの失敗にするのは、重みの無い地表の層の重ね合わせが
//! 描けないためである。無しを既定の重みへ黙って落とすと、塗り分けが消えた絵の理由が読み取れなくなる。

use super::super::super::{アセット実行時形式エラー, 材質割当エラー};
use super::super::bytes::読取位置;
use super::material_element::係数を読む;
use super::texture::テクスチャを読む工程;
use crate::asset::material_data::地表の層の重ね合わせデータ;
use crate::surface_layer_textures::地表層の数;

pub(super) fn 読む(
    入力: &mut 読取位置<'_>,
    テクスチャを読む: テクスチャを読む工程,
) -> Result<地表の層の重ね合わせデータ, アセット実行時形式エラー> {
    let Some(重みテクスチャ) = テクスチャを読む(入力)? else {
        return Err(材質割当エラー::地表の層の重ね合わせに重みテクスチャが無い.into());
    };
    let mut 層ごとのタイル倍率 = [0.0_f32; 地表層の数];
    for 倍率 in &mut 層ごとのタイル倍率 {
        *倍率 = 入力.f32()?;
    }
    let 金属度係数 = 係数を読む(入力)?;
    let 粗さ係数 = 係数を読む(入力)?;
    地表の層の重ね合わせデータ::生成する(重みテクスチャ, 層ごとのタイル倍率, 金属度係数, 粗さ係数)
        .map_err(|誤り| 材質割当エラー::地表の層の重ね合わせ不正(誤り).into())
}
