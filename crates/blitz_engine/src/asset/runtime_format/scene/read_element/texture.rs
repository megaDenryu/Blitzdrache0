//! テクスチャ1件を読む工程。受け取るのは読取位置、返すのは有無に応じた格納済みテクスチャである。
//! 版4までの並びと版5の並びの両方をここが持つ。どちらの並びで読むかは版ごとの組み立てが関数を選んで決める。
//! 版4までの並びは幅と高さと宣言長とRGBA8の画素列だけを持つため、読んだ値は格納形式RGBA8で縮小段を1本だけ持つ値へ写る。
//! これが版4から版5への昇格の変換にあたる。版4までのテクスチャは非圧縮の原寸1枚だけであり、この写しが正しい値になる。
//! 参照: `_doc/設計/アセット実行時形式.md`「シーン内容の版5」

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::読取位置;
use super::super::texture_format_tag::判別値から格納形式を読む;
use crate::asset::texture_storage::{
    テクスチャ格納形式, 格納済みテクスチャ, 格納済みテクスチャエラー, 縮小段の寸法
};

/// 縮小段1本ぶんの最小バイト数。宣言長のu64と、最も小さい段であるRGBA8の1x1の4バイトの合計である。
const 縮小段最小長: usize = 12;

/// テクスチャ1件を読む工程の署名。版ごとの組み立てが、自分の版の並びを読む工程をこの形で受け取る。
pub(in crate::asset::runtime_format::scene) type テクスチャを読む工程 =
    fn(&mut 読取位置<'_>) -> Result<Option<格納済みテクスチャ>, アセット実行時形式エラー>;

pub(in crate::asset::runtime_format::scene) fn 版4までのテクスチャを読む(
    入力: &mut 読取位置<'_>,
) -> Result<Option<格納済みテクスチャ>, アセット実行時形式エラー> {
    let Some((幅, 高さ)) = 有無と寸法を読む(入力)? else {
        return Ok(None);
    };
    let 宣言長 = 入力.u64()?;
    let 期待長 = 縮小段の寸法::生成する(幅, 高さ)
        .and_then(|寸法| テクスチャ格納形式::RGBA8.縮小段の格納バイト数を求める(寸法))
        .map_err(格納済みテクスチャエラー::from)?;
    if 期待長 != 宣言長 {
        return Err(アセット実行時形式エラー::テクスチャ長不一致 {
            期待長, 実長: 宣言長
        });
    }
    let 画素列 = 段のバイト列を読む(入力, 宣言長)?;
    Ok(Some(格納済みテクスチャ::生成する(
        幅,
        高さ,
        テクスチャ格納形式::RGBA8,
        vec![画素列],
    )?))
}

pub(in crate::asset::runtime_format) fn 版5のテクスチャを読む(
    入力: &mut 読取位置<'_>,
) -> Result<Option<格納済みテクスチャ>, アセット実行時形式エラー> {
    let Some((幅, 高さ)) = 有無と寸法を読む(入力)? else {
        return Ok(None);
    };
    let 格納形式 = 判別値から格納形式を読む(入力.u8()?)?;
    let 縮小段数 = 入力.件数(縮小段最小長)?;
    let mut 段ごとのバイト列 = Vec::with_capacity(縮小段数);
    for _ in 0..縮小段数 {
        let 宣言長 = 入力.u64()?;
        段ごとのバイト列.push(段のバイト列を読む(入力, 宣言長)?);
    }
    Ok(Some(格納済みテクスチャ::生成する(幅, 高さ, 格納形式, 段ごとのバイト列)?))
}

/// 有無の判別値と、有るときの幅と高さを読む。寸法が零のテクスチャはどの版でも存在しない。
fn 有無と寸法を読む(入力: &mut 読取位置<'_>) -> Result<Option<(u32, u32)>, アセット実行時形式エラー> {
    match 入力.u8()? {
        0 => Ok(None),
        1 => {
            let 幅 = 入力.u32()?;
            let 高さ = 入力.u32()?;
            if 幅 == 0 || 高さ == 0 {
                return Err(アセット実行時形式エラー::テクスチャ寸法ゼロ);
            }
            Ok(Some((幅, 高さ)))
        }
        不正 => Err(アセット実行時形式エラー::不正な有無判別値(不正)),
    }
}

fn 段のバイト列を読む(入力: &mut 読取位置<'_>, 宣言長: u64) -> Result<Vec<u8>, アセット実行時形式エラー> {
    let 長さ = usize::try_from(宣言長).map_err(|_| アセット実行時形式エラー::長さ表現不能)?;
    Ok(入力.バイト列(長さ)?.to_vec())
}
