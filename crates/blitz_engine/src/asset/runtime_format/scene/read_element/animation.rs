//! アニメーションクリップの名前、継続秒、ジョイント別TRSを読む。

mod channel;

use blitz_math::秒;

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::読取位置;
use crate::asset::{
    animation_clip::アニメーションクリップ, joint_channel::ジョイントアニメーションチャンネル, skin_data::スキンデータ
};

const クリップ最小長: usize = 15;
const 文字バイト長: usize = 1;
const ジョイントチャンネル最小長: usize = 3;
const 三成分値長: usize = 12;
const 四成分値長: usize = 16;

pub(in crate::asset::runtime_format::scene) fn 一覧を読む(
    入力: &mut 読取位置<'_>,
    スキン: Option<&スキンデータ>,
) -> Result<Vec<アニメーションクリップ>, アセット実行時形式エラー> {
    let クリップ数 = 入力.件数(クリップ最小長)?;
    if クリップ数 > 0 && スキン.is_none() {
        return Err(アセット実行時形式エラー::スキンなしアニメーション);
    }
    let ジョイント数 = スキン.map_or(0, |値| 値.ジョイント一覧.len());
    let mut 一覧 = Vec::with_capacity(クリップ数);
    for _ in 0..クリップ数 {
        一覧.push(クリップを読む(入力, ジョイント数)?);
    }
    Ok(一覧)
}

fn クリップを読む(
    入力: &mut 読取位置<'_>,
    ジョイント数: usize,
) -> Result<アニメーションクリップ, アセット実行時形式エラー> {
    let 名前長 = 入力.件数(文字バイト長)?;
    let 名前 = std::str::from_utf8(入力.バイト列(名前長)?)
        .map_err(|_| アセット実行時形式エラー::不正な文字列)?
        .to_owned();
    let 継続秒 = 入力.f32()?;
    if 継続秒 < 0.0 {
        return Err(アセット実行時形式エラー::アニメーション継続秒不正);
    }
    let チャンネル数 = 入力.件数(ジョイントチャンネル最小長)?;
    if チャンネル数 != ジョイント数 {
        return Err(アセット実行時形式エラー::アニメーションジョイント数不一致 {
            チャンネル数, ジョイント数
        });
    }
    let mut ジョイントチャンネル一覧 = Vec::with_capacity(チャンネル数);
    for _ in 0..チャンネル数 {
        ジョイントチャンネル一覧.push(ジョイントアニメーションチャンネル {
            平行移動: channel::読む(入力, 三成分値長, 継続秒, |入力: &mut 読取位置<'_>| {
                Ok([入力.f32()?, 入力.f32()?, 入力.f32()?])
            })?,
            回転: channel::読む(入力, 四成分値長, 継続秒, |入力: &mut 読取位置<'_>| {
                Ok([入力.f32()?, 入力.f32()?, 入力.f32()?, 入力.f32()?])
            })?,
            スケール: channel::読む(入力, 三成分値長, 継続秒, |入力: &mut 読取位置<'_>| {
                Ok([入力.f32()?, 入力.f32()?, 入力.f32()?])
            })?,
        });
    }
    Ok(アニメーションクリップ {
        名前,
        継続秒: 秒::生成する(継続秒),
        ジョイントチャンネル一覧,
    })
}
