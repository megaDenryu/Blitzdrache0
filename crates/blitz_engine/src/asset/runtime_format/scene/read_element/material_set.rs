//! 版4以降の材質集合を読む工程。受け取るのは読取位置と版ごとの要素の読み方、返すのは「材質スロットID→材質」の非空な対応である。
//! テクスチャの並びと材質の種別の枝だけが版で変わるため、その2つの読み方を引数で受け取り、材質集合の並びと検査はここが1つだけ持つ。
//! 材質1件ごとの検証(特徴集合の双方向の一致、地表の層の重ね合わせのタイル倍率と係数)は種別ごとの本体が持つ。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「材質特徴集合の初期確定」

use super::super::super::{アセット実行時形式エラー, 材質割当エラー};
use super::super::bytes::読取位置;
use super::version_codec::版ごとの要素の読み方;
use crate::asset::material_set::材質集合;
use crate::asset::material_slot_assignment::材質スロット割当;
use crate::asset::material_slot_id::材質スロットID;

/// 材質1件の最小バイト数。金属粗さPBRのスロットID4 + 種別4 + 特徴集合4 + テクスチャ有無1×3 + 係数4×6の合計である。
/// 地表の層の重ね合わせの1件はこれより長いため、確保前の下限としてはこの値で足りる。
pub(super) const 材質最小長: usize = 39;

pub(in crate::asset::runtime_format::scene) fn 読む(
    入力: &mut 読取位置<'_>,
    読み方: 版ごとの要素の読み方,
) -> Result<材質集合, アセット実行時形式エラー> {
    let 件数 = 入力.件数(材質最小長)?;
    let mut 割当一覧 = Vec::with_capacity(件数);
    for _ in 0..件数 {
        let スロット = 材質スロットID::生成する(入力.u32()?);
        割当一覧.push(材質スロット割当 {
            スロット,
            マテリアル: (読み方.材質1件())(入力, 読み方.テクスチャ1件())?,
        });
    }
    Ok(材質集合::生成する(割当一覧).map_err(材質割当エラー::材質集合不正)?)
}
