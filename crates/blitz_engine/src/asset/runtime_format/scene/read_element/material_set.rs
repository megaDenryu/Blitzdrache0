//! 版4の材質集合を読む工程。受け取るのは読取位置、返すのは「材質スロットID→材質」の非空な対応である。
//! 材質1件ごとに、直列化された材質特徴集合が実際に読めたテクスチャの有無と両方向で一致することをここで確かめる。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「材質特徴集合の初期確定」

use super::super::super::{アセット実行時形式エラー, 材質割当エラー};
use super::super::bytes::読取位置;
use super::material_element::{テクスチャを読む, 係数を読む, 金属粗さPBRの種別番号};
use crate::asset::material_data::マテリアルデータ;
use crate::asset::material_set::材質集合;
use crate::asset::material_slot_assignment::材質スロット割当;
use crate::asset::material_slot_id::材質スロットID;
use crate::asset::pbr_material_data::{材質特徴集合, 金属粗さPBRデータ};

/// 材質1件の最小バイト数。スロットID4 + 種別4 + 特徴集合4 + テクスチャ有無1×3 + 係数4×6の合計である。
pub(super) const 材質最小長: usize = 39;

pub(in crate::asset::runtime_format::scene) fn 読む(入力: &mut 読取位置<'_>) -> Result<材質集合, アセット実行時形式エラー> {
    let 件数 = 入力.件数(材質最小長)?;
    let mut 割当一覧 = Vec::with_capacity(件数);
    for _ in 0..件数 {
        let スロット = 材質スロットID::生成する(入力.u32()?);
        割当一覧.push(材質スロット割当 {
            スロット,
            マテリアル: 材質を読む(入力)?,
        });
    }
    Ok(材質集合::生成する(割当一覧).map_err(材質割当エラー::材質集合不正)?)
}

fn 材質を読む(入力: &mut 読取位置<'_>) -> Result<マテリアルデータ, アセット実行時形式エラー> {
    let 種別 = 入力.u32()?;
    if 種別 != 金属粗さPBRの種別番号 {
        return Err(アセット実行時形式エラー::未知のマテリアル種別(種別));
    }
    let 宣言された特徴集合 = 材質特徴集合::生値から復元する(入力.u32()?).map_err(材質割当エラー::材質特徴集合不正)?;
    let データ = 金属粗さPBRデータ {
        ベースカラー: テクスチャを読む(入力)?,
        金属粗さ: テクスチャを読む(入力)?,
        法線マップ: テクスチャを読む(入力)?,
        ベースカラー係数: [係数を読む(入力)?, 係数を読む(入力)?, 係数を読む(入力)?, 係数を読む(入力)?],
        金属度係数: 係数を読む(入力)?,
        粗さ係数: 係数を読む(入力)?,
    };
    データ
        .宣言された特徴集合と照合する(宣言された特徴集合)
        .map_err(材質割当エラー::材質特徴集合不正)?;
    Ok(マテリアルデータ::金属粗さPBR(データ))
}
