//! 種別番号の後に続く、金属粗さPBRの本体を読む工程。受け取るのは読取位置とテクスチャ1件を読む工程、
//! 返すのは検証済みの金属粗さPBRデータである。
//!
//! 種別番号を読まないのは、どの種別が来たかを判別するのが呼び出し元(版ごとの材質の読み方)だからである。
//! 本体をここへ分けると、版4と版5の「種別1しか無い並び」と版6の「種別で枝が分かれる並び」が同じ本体を通る。

use super::super::super::{アセット実行時形式エラー, 材質割当エラー};
use super::super::bytes::読取位置;
use super::material_element::係数を読む;
use super::texture::テクスチャを読む工程;
use crate::asset::pbr_material_data::{材質特徴集合, 金属粗さPBRデータ};

pub(super) fn 読む(
    入力: &mut 読取位置<'_>,
    テクスチャを読む: テクスチャを読む工程,
) -> Result<金属粗さPBRデータ, アセット実行時形式エラー> {
    let 宣言された特徴集合 = 材質特徴集合::生値から復元する(入力.u32()?).map_err(材質割当エラー::材質特徴集合不正)?;
    let データ = 金属粗さPBRデータ {
        ベースカラー: テクスチャを読む(入力)?,
        金属粗さ: テクスチャを読む(入力)?,
        法線マップ: テクスチャを読む(入力)?,
        ベースカラー係数: [係数を読む(入力)?, 係数を読む(入力)?, 係数を読む(入力)?, 係数を読む(入力)?],
        金属度係数: 係数を読む(入力)?,
        粗さ係数: 係数を読む(入力)?,
    };
    データ
        .宣言された特徴集合と照合する(宣言された特徴集合)
        .map_err(材質割当エラー::材質特徴集合不正)?;
    Ok(データ)
}
