//! インスタンス群の配置列と境界を読む。個体1件はチャンクアンカー相対のTRSであり、境界は群の包囲領域と原型の境界球である。
//! 値の検査は`個体配置`・`軸平行包囲領域`・`境界球`の生成関数が持つため、ここは並びの復元だけを行う。

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::読取位置;
use crate::asset::instance::{個体配置, 境界球, 群境界, 軸平行包囲領域};

/// 個体配置1件のバイト数。平行移動3・回転4・スケール3のf32である。
pub(in crate::asset::runtime_format::scene) const 個体配置長: usize = 40;

pub(in crate::asset::runtime_format::scene) fn 配置列を読む(
    入力: &mut 読取位置<'_>,
) -> Result<Vec<個体配置>, アセット実行時形式エラー> {
    let 個体数 = 入力.件数(個体配置長)?;
    let mut 配置一覧 = Vec::with_capacity(個体数);
    for _ in 0..個体数 {
        let 平行移動 = [入力.f32()?, 入力.f32()?, 入力.f32()?];
        let 回転 = [入力.f32()?, 入力.f32()?, 入力.f32()?, 入力.f32()?];
        let スケール = [入力.f32()?, 入力.f32()?, 入力.f32()?];
        配置一覧.push(個体配置::生成する(平行移動, 回転, スケール)?);
    }
    Ok(配置一覧)
}

pub(in crate::asset::runtime_format::scene) fn 境界を読む(
    入力: &mut 読取位置<'_>
) -> Result<群境界, アセット実行時形式エラー> {
    let 最小 = [入力.f32()?, 入力.f32()?, 入力.f32()?];
    let 最大 = [入力.f32()?, 入力.f32()?, 入力.f32()?];
    let 包囲領域 = 軸平行包囲領域::生成する(最小, 最大)?;
    let 中心 = [入力.f32()?, 入力.f32()?, 入力.f32()?];
    let 球 = 境界球::生成する(中心, 入力.f32()?)?;
    Ok(群境界::生成する(包囲領域, 球))
}
