//! 版1の高さ場内容を境界検査して復元する。標本の列を確保する前に、格子点数の積と1標本のバイト数の積が
//! 残りバイト数に収まることを確かめる。件数が1つのu32でなく2方向の積で決まるため、確保前の検査を明示的に呼ぶ。

use blitz_math::{メートル, 大域メートル};

use super::super::height_field_error::高さ場実行時形式エラー;
use super::super::scene::bytes::読取位置;
use super::super::アセット実行時形式エラー;
use crate::height_field::{高さ場, 高さ場諸元};

/// 高さ1つのバイト数。
const 標本のバイト数: usize = 4;

pub(super) fn 高さ場内容を読む(内容: &[u8]) -> Result<高さ場, 高さ場実行時形式エラー> {
    let mut 入力 = 読取位置::新規(内容);
    let 格子原点の東成分 = 大域メートル::生成する(入力.f64()?);
    let 格子原点の南成分 = 大域メートル::生成する(入力.f64()?);
    let 格子間隔 = メートル::生成する(入力.f32()?);
    let 東方向の格子点数 = 入力.u32()?;
    let 南方向の格子点数 = 入力.u32()?;
    let 諸元 = 高さ場諸元::生成する(格子原点の東成分, 格子原点の南成分, 格子間隔, 東方向の格子点数, 南方向の格子点数)?;
    let 標本数 = usize::try_from(諸元.標本数()).map_err(|_| アセット実行時形式エラー::長さ表現不能)?;
    入力.宣言件数を確保前に検査する(標本数, 標本のバイト数)?;
    let mut 高さ一覧 = Vec::with_capacity(標本数);
    for _ in 0..標本数 {
        高さ一覧.push(メートル::生成する(入力.f32()?));
    }
    入力.完了を検査する()?;
    Ok(高さ場::生成する(諸元, 高さ一覧)?)
}
