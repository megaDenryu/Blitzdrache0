//! 高さ場を版1内容へ決定的に書く。並びは諸元・標本の順であり、標本は高さ場の保持順(南が外側、東が内側)をそのまま使う。
//! 保持順をそのまま使うため、同じ高さ場からは常に同じバイト列を得る。

use super::super::scene::bytes::書込先;
use super::super::アセット実行時形式エラー;
use crate::height_field::高さ場;

pub(super) fn 高さ場内容を書く(高さ場: &高さ場) -> Result<Vec<u8>, アセット実行時形式エラー> {
    let 諸元 = 高さ場.諸元();
    let mut 出力 = 書込先::新規();
    出力.f64(諸元.格子原点の東成分().値())?;
    出力.f64(諸元.格子原点の南成分().値())?;
    出力.f32(諸元.格子間隔().値())?;
    出力.u32(諸元.東方向の格子点数());
    出力.u32(諸元.南方向の格子点数());
    for 高さ in 高さ場.高さ一覧() {
        出力.f32(高さ.値())?;
    }
    Ok(出力.完了する())
}
