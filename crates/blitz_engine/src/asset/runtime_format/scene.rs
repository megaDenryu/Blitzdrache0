pub fn シーンを実行時形式へ格納する(シーン: &シーンデータ) -> Result<Vec<u8>, アセット実行時形式エラー> {
    v5::シーン内容を格納する(シーン)
}

pub fn 実行時形式からシーンを読む(バイト列: &[u8]) -> Result<シーンデータ, アセット実行時形式エラー> {
    let アセット = 実行時アセットを開く(バイト列)?;
    match アセット.種別 {
        実行時アセット種別::シーン => {}
        種別 @ (実行時アセット種別::カタログ | 実行時アセット種別::チャンク目録 | 実行時アセット種別::高さ場) =>
        {
            return Err(アセット実行時形式エラー::アセット種別不一致 {
                期待: 実行時アセット種別::シーン.番号(),
                実際: 種別.番号(),
            });
        }
    }
    match アセット.形式版 {
        アセット形式版::V1 => Ok(v1::シーン内容を読む(アセット.内容)?.最新へ変換する()),
        アセット形式版::V2 => Ok(v2::シーン内容を読む(アセット.内容)?.最新へ変換する()),
        アセット形式版::V3 => Ok(v3::シーン内容を読む(アセット.内容)?.最新へ変換する()),
        アセット形式版::V4 => v4::シーン内容を読む(アセット.内容),
        アセット形式版::V5 => v5::シーン内容を読む(アセット.内容),
    }
}
