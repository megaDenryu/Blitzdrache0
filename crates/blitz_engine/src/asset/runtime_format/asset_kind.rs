//! 実行時アセットの種別と、共通ヘッダーが運ぶ番号との対応。担当するのは、この形式で運べる中身の種類を
//! 数え上げることと、番号との相互の写しを1箇所で持つことである。
//!
//! 注意: 番号は焼いたファイルの中に残るため、既存の枝の番号を付け替えてはならない。種別を足すときは
//! 未使用の番号を新しく採る。
//! 参照: `高さ場`は`_doc/設計/ゲーム制作アーキテクチャ.md`「判断7: 地図の正本を持ち、生成は2系統に分ける」、`地表層テクスチャ集`は`_doc/設計/マルチマテリアルと材質境界.md`

use super::アセット実行時形式エラー;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 実行時アセット種別 {
    シーン,
    カタログ,
    チャンク目録,
    高さ場,             // 世界の高さを実行中に参照する
    地表層テクスチャ集, // 地表材質の層に貼るタイルテクスチャを世界に1つだけ置く
}

impl 実行時アセット種別 {
    pub fn 番号(self) -> u32 {
        match self {
            Self::シーン => 1,
            Self::カタログ => 2,
            Self::チャンク目録 => 3,
            Self::高さ場 => 4,
            Self::地表層テクスチャ集 => 5,
        }
    }

    pub(super) fn 番号から読む(番号: u32) -> Result<Self, アセット実行時形式エラー> {
        match 番号 {
            1 => Ok(Self::シーン),
            2 => Ok(Self::カタログ),
            3 => Ok(Self::チャンク目録),
            4 => Ok(Self::高さ場),
            5 => Ok(Self::地表層テクスチャ集),
            未知 => Err(アセット実行時形式エラー::未知のアセット種別(未知)),
        }
    }
}
