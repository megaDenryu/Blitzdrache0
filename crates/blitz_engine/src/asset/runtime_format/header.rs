//! 24バイトの共通ヘッダーを決定的に書き、検証して読む。

use super::{
    アセット実行時形式エラー, アセット形式版, ヘッダー長, 固定識別値, 実行時アセット, 実行時アセット種別
};

/// 形式版を呼び出し側から受けるのは、種別ごとに最新の版が違うためである。既定値を置くと、種別を増やしたときに古い版で書き出す経路が無言で生まれる。
pub fn 実行時アセットを格納する(
    形式版: アセット形式版,
    種別: 実行時アセット種別,
    内容: &[u8],
) -> Result<Vec<u8>, アセット実行時形式エラー> {
    let 内容長 = u64::try_from(内容.len()).map_err(|_| アセット実行時形式エラー::内容長表現不能)?;
    let 全長 = ヘッダー長.checked_add(内容.len()).ok_or(アセット実行時形式エラー::内容長表現不能)?;
    let mut 結果 = Vec::with_capacity(全長);
    結果.extend_from_slice(&固定識別値);
    結果.extend_from_slice(&形式版.番号().to_le_bytes());
    結果.extend_from_slice(&種別.番号().to_le_bytes());
    結果.extend_from_slice(&内容長.to_le_bytes());
    結果.extend_from_slice(内容);
    Ok(結果)
}

pub fn 実行時アセットを開く(バイト列: &[u8]) -> Result<実行時アセット<'_>, アセット実行時形式エラー> {
    if バイト列.len() < ヘッダー長 {
        return Err(アセット実行時形式エラー::ヘッダー不足 { 実長: バイト列.len() });
    }
    if バイト列.get(0..8) != Some(固定識別値.as_slice()) {
        return Err(アセット実行時形式エラー::固定識別値不一致);
    }
    let 形式版 = アセット形式版::番号から読む(u32を読む(バイト列, 8))?;
    let 種別 = 実行時アセット種別::番号から読む(u32を読む(バイト列, 12))?;
    let 宣言長 = u64を読む(バイト列, 16);
    let 内容 = &バイト列[ヘッダー長..];
    let 実長 = u64::try_from(内容.len()).map_err(|_| アセット実行時形式エラー::内容長表現不能)?;
    if 宣言長 != 実長 {
        return Err(アセット実行時形式エラー::内容長不一致 { 宣言長, 実長 });
    }
    Ok(実行時アセット { 形式版, 種別, 内容 })
}

fn u32を読む(バイト列: &[u8], 開始: usize) -> u32 {
    u32::from_le_bytes([バイト列[開始], バイト列[開始 + 1], バイト列[開始 + 2], バイト列[開始 + 3]])
}

fn u64を読む(バイト列: &[u8], 開始: usize) -> u64 {
    u64::from_le_bytes([
        バイト列[開始],
        バイト列[開始 + 1],
        バイト列[開始 + 2],
        バイト列[開始 + 3],
        バイト列[開始 + 4],
        バイト列[開始 + 5],
        バイト列[開始 + 6],
        バイト列[開始 + 7],
    ])
}
