//! 版1の金属粗さPBRマテリアルとRGBA8テクスチャを読む。

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::読取位置;
use crate::asset::material_data::マテリアルデータ;
use crate::asset::pbr_material_data::金属粗さPBRデータ;
use crate::asset::texture_data::テクスチャデータ;

pub(super) fn 読む(入力: &mut 読取位置<'_>) -> Result<マテリアルデータ, アセット実行時形式エラー> {
    let 種別 = 入力.u32()?;
    if 種別 != 1 {
        return Err(アセット実行時形式エラー::未知のマテリアル種別(種別));
    }
    Ok(マテリアルデータ::金属粗さPBR(金属粗さPBRデータ {
        ベースカラー: テクスチャを読む(入力)?,
        金属粗さ: テクスチャを読む(入力)?,
        法線マップ: テクスチャを読む(入力)?,
        ベースカラー係数: [係数を読む(入力)?, 係数を読む(入力)?, 係数を読む(入力)?, 係数を読む(入力)?],
        金属度係数: 係数を読む(入力)?,
        粗さ係数: 係数を読む(入力)?,
    }))
}

fn 係数を読む(入力: &mut 読取位置<'_>) -> Result<f32, アセット実行時形式エラー> {
    let 値 = 入力.f32()?;
    if (0.0..=1.0).contains(&値) {
        Ok(値)
    } else {
        Err(アセット実行時形式エラー::マテリアル係数範囲外)
    }
}

fn テクスチャを読む(入力: &mut 読取位置<'_>) -> Result<Option<テクスチャデータ>, アセット実行時形式エラー> {
    match 入力.u8()? {
        0 => Ok(None),
        1 => {
            let 幅 = 入力.u32()?;
            let 高さ = 入力.u32()?;
            if 幅 == 0 || 高さ == 0 {
                return Err(アセット実行時形式エラー::テクスチャ寸法ゼロ);
            }
            let 宣言長 = 入力.u64()?;
            let 期待長 = u64::from(幅)
                .checked_mul(u64::from(高さ))
                .and_then(|画素数| 画素数.checked_mul(4))
                .ok_or(アセット実行時形式エラー::長さ表現不能)?;
            if 期待長 != 宣言長 {
                return Err(アセット実行時形式エラー::テクスチャ長不一致 {
                    期待長, 実長: 宣言長
                });
            }
            let 長さ = usize::try_from(宣言長).map_err(|_| アセット実行時形式エラー::長さ表現不能)?;
            Ok(Some(テクスチャデータ {
                幅,
                高さ,
                rgba8: 入力.バイト列(長さ)?.to_vec(),
            }))
        }
        不正 => Err(アセット実行時形式エラー::不正な有無判別値(不正)),
    }
}
