//! アニメーションクリップとTRSキーフレームを書く。

mod channel;

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::書込先;
use crate::asset::animation_clip::アニメーションクリップ;

pub(super) fn 一覧を書く(
    出力: &mut 書込先,
    一覧: &[アニメーションクリップ],
    ジョイント数: Option<usize>,
) -> Result<(), アセット実行時形式エラー> {
    出力.件数(一覧.len())?;
    for クリップ in 一覧 {
        クリップを書く(出力, クリップ, ジョイント数)?;
    }
    Ok(())
}

fn クリップを書く(
    出力: &mut 書込先,
    クリップ: &アニメーションクリップ,
    ジョイント数: Option<usize>,
) -> Result<(), アセット実行時形式エラー> {
    let Some(ジョイント数) = ジョイント数 else {
        return Err(アセット実行時形式エラー::スキンなしアニメーション);
    };
    if クリップ.ジョイントチャンネル一覧.len() != ジョイント数 {
        return Err(アセット実行時形式エラー::アニメーションジョイント数不一致 {
            チャンネル数: クリップ.ジョイントチャンネル一覧.len(),
            ジョイント数,
        });
    }
    出力.件数(クリップ.名前.len())?;
    出力.バイト列(クリップ.名前.as_bytes());
    let 継続秒 = クリップ.継続秒.値();
    if 継続秒 < 0.0 || !継続秒.is_finite() {
        return Err(アセット実行時形式エラー::アニメーション継続秒不正);
    }
    出力.f32(継続秒)?;
    出力.件数(ジョイント数)?;
    for チャンネル in &クリップ.ジョイントチャンネル一覧 {
        channel::書く(出力, チャンネル.平行移動.as_ref(), 継続秒)?;
        channel::書く(出力, チャンネル.回転.as_ref(), 継続秒)?;
        channel::書く(出力, チャンネル.スケール.as_ref(), 継続秒)?;
    }
    Ok(())
}
