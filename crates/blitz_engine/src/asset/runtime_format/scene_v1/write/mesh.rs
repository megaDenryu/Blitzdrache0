//! メッシュと任意の頂点スキン属性を書く。

use super::super::super::アセット実行時形式エラー;
use super::super::bytes::書込先;
use crate::asset::{mesh_data::メッシュデータ, skin_vertex_attribute::スキン頂点属性, vertex_attribute::メッシュ頂点属性};

pub(super) fn 書く(
    出力: &mut 書込先, メッシュ: &メッシュデータ, ジョイント数: Option<usize>
) -> Result<(), アセット実行時形式エラー> {
    基本内容を検査する(メッシュ)?;
    出力.件数(メッシュ.頂点一覧.len())?;
    for 頂点 in &メッシュ.頂点一覧 {
        頂点を書く(出力, 頂点)?;
    }
    出力.件数(メッシュ.インデックス一覧.len())?;
    for &添字 in &メッシュ.インデックス一覧 {
        出力.u32(添字);
    }
    スキン頂点属性を書く(出力, メッシュ, ジョイント数)
}

fn 基本内容を検査する(メッシュ: &メッシュデータ) -> Result<(), アセット実行時形式エラー> {
    if メッシュ.頂点一覧.is_empty() {
        return Err(アセット実行時形式エラー::頂点なし);
    }
    if メッシュ.インデックス一覧.is_empty() {
        return Err(アセット実行時形式エラー::インデックスなし);
    }
    for &インデックス in &メッシュ.インデックス一覧 {
        if usize::try_from(インデックス).map_or(true, |値| 値 >= メッシュ.頂点一覧.len()) {
            return Err(アセット実行時形式エラー::インデックス範囲外 {
                インデックス,
                頂点数: メッシュ.頂点一覧.len(),
            });
        }
    }
    Ok(())
}

fn 頂点を書く(出力: &mut 書込先, 頂点: &メッシュ頂点属性) -> Result<(), アセット実行時形式エラー> {
    for 値 in 頂点.位置.into_iter().chain(頂点.法線).chain(頂点.接線).chain(頂点.uv) {
        出力.f32(値)?;
    }
    Ok(())
}

fn スキン頂点属性を書く(
    出力: &mut 書込先,
    メッシュ: &メッシュデータ,
    ジョイント数: Option<usize>,
) -> Result<(), アセット実行時形式エラー> {
    let Some(属性一覧) = &メッシュ.スキン頂点属性一覧 else {
        出力.u8(0);
        return Ok(());
    };
    let Some(ジョイント数) = ジョイント数 else {
        return Err(アセット実行時形式エラー::スキンなし頂点属性);
    };
    if 属性一覧.len() != メッシュ.頂点一覧.len() {
        return Err(アセット実行時形式エラー::スキン頂点属性数不一致 {
            属性数: 属性一覧.len(),
            頂点数: メッシュ.頂点一覧.len(),
        });
    }
    出力.u8(1);
    出力.件数(属性一覧.len())?;
    for 属性 in 属性一覧 {
        属性を書く(出力, 属性, ジョイント数)?;
    }
    Ok(())
}

fn 属性を書く(
    出力: &mut 書込先, 属性: &スキン頂点属性, ジョイント数: usize
) -> Result<(), アセット実行時形式エラー> {
    for &添字 in &属性.ジョイント {
        if usize::from(添字) >= ジョイント数 {
            return Err(アセット実行時形式エラー::スキンジョイント範囲外 {
                ジョイント添字: 添字,
                ジョイント数,
            });
        }
        出力.u16(添字);
    }
    for &ウェイト in &属性.ウェイト {
        出力.f32(ウェイト)?;
    }
    Ok(())
}
