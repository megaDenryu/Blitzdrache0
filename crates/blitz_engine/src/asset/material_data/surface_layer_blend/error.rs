//! 地表の層の重ね合わせのマテリアルデータが拒む状態。生成の手前で拒むため、拒む理由もこの1つの型に集める。
//!
//! 破れた値そのものを持たないのは、この型が実行時形式の失敗の語彙(`材質割当エラー`)へ畳まれ、
//! その語彙が`Copy`と`Eq`を備えるためである。どの層のどの係数が破れたかは名指しで分かる。

use thiserror::Error;

#[derive(Debug, Error, Clone, Copy, PartialEq, Eq)]
pub enum 地表の層の重ね合わせデータエラー {
    #[error("層{層番号}のタイル倍率が正の有限値でない")]
    タイル倍率が正の有限値でない { 層番号: usize },
    #[error("地表の層の重ね合わせの{係数の名前}が0以上1以下の範囲外である")]
    係数範囲外 { 係数の名前: &'static str },
}
