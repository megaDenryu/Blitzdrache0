//! 地表の層の重ね合わせのマテリアルデータ。担当するのは、チャンクごとに違う塗り分けの重みと、
//! 層ごとにタイルを何倍で貼るかを1つの組として保つことである。
//!
//! 層のタイルそのものを持たないのは、タイルが世界に1つだけ置く共有アセットだからである。チャンクごとに
//! タイルを焼くと、同じ絵がチャンクの数だけ実行時形式へ入る。タイルを材質へ結ぶのは、実行時形式を読んだ後の
//! 変換の段である(参照: `_doc/設計/マルチマテリアルと材質境界.md`「地表の層の重ね合わせ」)。
//!
//! 重みを`Option`で持たないのは、重みの無い地表の層の重ね合わせが描けないためである。「無し」は値の不在ではなく、
//! この枝が成立しないことを意味する。

mod error;

use crate::asset::texture_storage::格納済みテクスチャ;
use crate::surface_layer_textures::地表層の数;

pub use error::地表の層の重ね合わせデータエラー;

#[derive(Debug, Clone, PartialEq)]
pub struct 地表の層の重ね合わせデータ {
    重みテクスチャ: 格納済みテクスチャ,
    層ごとのタイル倍率: [f32; 地表層の数],
    金属度係数: f32,
    粗さ係数: f32,
}

impl 地表の層の重ね合わせデータ {
    pub fn 生成する(
        重みテクスチャ: 格納済みテクスチャ,
        層ごとのタイル倍率: [f32; 地表層の数],
        金属度係数: f32,
        粗さ係数: f32,
    ) -> Result<Self, 地表の層の重ね合わせデータエラー> {
        for (層番号, 倍率) in 層ごとのタイル倍率.iter().enumerate() {
            if !倍率.is_finite() || *倍率 <= 0.0 {
                return Err(地表の層の重ね合わせデータエラー::タイル倍率が正の有限値でない { 層番号 });
            }
        }
        for (係数の名前, 係数) in [("金属度係数", 金属度係数), ("粗さ係数", 粗さ係数)] {
            if !(0.0..=1.0).contains(&係数) {
                return Err(地表の層の重ね合わせデータエラー::係数範囲外 { 係数の名前 });
            }
        }
        Ok(Self {
            重みテクスチャ,
            層ごとのタイル倍率,
            金属度係数,
            粗さ係数,
        })
    }

    pub fn 重みテクスチャ(&self) -> &格納済みテクスチャ {
        &self.重みテクスチャ
    }

    /// 層番号を配列の添字として使う並び。重みのRGBA成分の並びと同じであり、層0が草・層1が泥・層2が岩・層3が砂である。
    pub fn 層ごとのタイル倍率(&self) -> [f32; 地表層の数] {
        self.層ごとのタイル倍率
    }

    pub fn 金属度係数(&self) -> f32 {
        self.金属度係数
    }

    pub fn 粗さ係数(&self) -> f32 {
        self.粗さ係数
    }
}
