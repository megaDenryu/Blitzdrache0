//! シーンデータ: 描画対象の非空の一覧とアセット由来の付随情報。

use std::path::PathBuf;

use super::animation_clip::アニメーションクリップ;
use super::render_object_data::描画対象データ;
use super::skin_data::スキンデータ;
use crate::static_shape::チャンクの静的物理形状;

/// 1つ以上の描画対象を持つシーン。
///
/// `参照ファイル一覧` はローダが実際に読んだファイル群(主ファイル・外部バッファ・
/// 外部画像)。アセットホットリロードのmtime監視対象として使う。
///
/// `スキン`と`アニメーション一覧`はスキン付きメッシュのみ値を持つ(判断42)。
/// スキン無しシーンは`スキン: None`・`アニメーション一覧: 空のVec`で、既存の静的シーンの
/// 読込結果は無変更のまま通る。
///
/// `静的物理形状`は描画に使わない。描画対象のメッシュから導いたものではなく、部品カタログが持つ部品ごとの直方体を
/// 正本として焼いた別物であり、生成する時点では空である。焼いた形状を持たせるのは`静的物理形状を添える`だけである。
#[derive(Debug, Clone, PartialEq)]
pub struct シーンデータ {
    描画対象一覧: Vec<描画対象データ>,
    静的物理形状: チャンクの静的物理形状,
    pub 参照ファイル一覧: Vec<PathBuf>,
    pub スキン: Option<スキンデータ>,
    pub アニメーション一覧: Vec<アニメーションクリップ>,
}

impl シーンデータ {
    /// 先頭を別引数にすることで、空の描画対象一覧を構築不能にする。
    pub fn 生成する(
        先頭の描画対象: 描画対象データ,
        残りの描画対象一覧: Vec<描画対象データ>,
        参照ファイル一覧: Vec<PathBuf>,
        スキン: Option<スキンデータ>,
        アニメーション一覧: Vec<アニメーションクリップ>,
    ) -> Self {
        let mut 描画対象一覧 = Vec::with_capacity(1 + 残りの描画対象一覧.len());
        描画対象一覧.push(先頭の描画対象);
        描画対象一覧.extend(残りの描画対象一覧);
        Self {
            描画対象一覧,
            静的物理形状: チャンクの静的物理形状::空を作る(),
            参照ファイル一覧,
            スキン,
            アニメーション一覧,
        }
    }

    /// 焼いた静的物理形状を添えたシーンを返す。建物を置いたチャンクを焼く工程だけがこれを呼ぶ。
    pub fn 静的物理形状を添える(self, 静的物理形状: チャンクの静的物理形状) -> Self {
        Self { 静的物理形状, ..self }
    }

    /// 静的物理形状を切り離し、形状と残りのシーンを返す。描画へ渡す経路とチャンクごとの保管へ入れる経路が
    /// ここで分かれるため、切り離した後のシーンは形状を持たない。写しを作らないのは、同じ形状が2箇所に在る間に
    /// 片方だけが更新される状態を作らないためである。
    pub fn 静的物理形状を取り分ける(self) -> (Self, チャンクの静的物理形状) {
        let 形状 = self.静的物理形状;
        (
            Self {
                静的物理形状: チャンクの静的物理形状::空を作る(),
                ..self
            },
            形状,
        )
    }

    pub fn 静的物理形状(&self) -> &チャンクの静的物理形状 {
        &self.静的物理形状
    }

    pub fn 描画対象一覧(&self) -> &[描画対象データ] {
        &self.描画対象一覧
    }

    pub fn 先頭の描画対象(&self) -> &描画対象データ {
        match self.描画対象一覧.first() {
            Some(描画対象) => 描画対象,
            None => panic!("シーンデータは1つ以上の描画対象を持つ不変条件に違反した"),
        }
    }
}
