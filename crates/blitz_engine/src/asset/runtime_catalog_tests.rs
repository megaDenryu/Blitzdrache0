#[test]
fn カタログを安定id順で決定的に往復する() {
    let mut カタログ = カタログ::空を作る();
    カタログ.世界の由来を記録する(世界の由来::種から生成した {
        乱数の種: 世界の乱数の種::生成する(20260814),
        生成器の版: 世界の生成器の版::生成する(3),
    });
    登録する(&mut カタログ, "fox", 100, 200, 300);
    登録する(&mut カタログ, "quad", 4, 6, 64);
    let Ok(一回目) = カタログを実行時形式へ格納する(&カタログ) else {
        panic!("カタログを実行時形式へ格納できなかった");
    };
    let Ok(二回目) = カタログを実行時形式へ格納する(&カタログ) else {
        panic!("カタログを2回目の実行時形式へ格納できなかった");
    };
    assert_eq!(一回目, 二回目);
    let Ok(復元) = 実行時形式からカタログを読む(&一回目) else {
        panic!("実行時形式からカタログを復元できなかった");
    };
    let Ok(fox) = アセットID::生成する("fox") else {
        panic!("試験用IDを生成できなかった");
    };
    let Some(項目) = 復元.項目を参照する(&fox) else {
        panic!("復元カタログにfoxが無かった");
    };
    assert_eq!(項目.実行時パス(), Path::new("fox.blitzasset"));
    assert_eq!(項目.ソース依存一覧(), [PathBuf::from("assets/fox.glb")]);
    assert_eq!(項目.メタデータ().頂点数, 100);
    assert_eq!(復元.世界の由来(), カタログ.世界の由来());
}

#[test]
fn シーンをカタログとして読むと種別不一致になる() {
    let シーン = 静的シーンを作る(vec![10, 20, 30, 255], 0.2);
    let Ok(バイト列) = シーンを実行時形式へ格納する(&シーン) else {
        panic!("試験用シーンを格納できなかった");
    };
    assert!(matches!(
        実行時形式からカタログを読む(&バイト列),
        Err(アセット実行時形式エラー::アセット種別不一致 { .. })
    ));
}

#[test]
fn 種から生成した世界の生成器の版0を拒む() {
    let mut カタログ = カタログ::空を作る();
    カタログ.世界の由来を記録する(世界の由来::種から生成した {
        乱数の種: 世界の乱数の種::生成する(1),
        生成器の版: 世界の生成器の版::生成する(1),
    });
    let Ok(mut バイト列) = カタログを実行時形式へ格納する(&カタログ) else {
        panic!("カタログを格納できなかった");
    };
    バイト列[32..36].copy_from_slice(&0_u32.to_le_bytes());
    assert!(matches!(
        実行時形式からカタログを読む(&バイト列),
        Err(アセット実行時形式エラー::未知の世界の由来(1))
    ));
}

fn 登録する(カタログ: &mut カタログ, 名前: &str, 頂点数: u64, インデックス数: u64, テクスチャ格納バイト数: u64) {
    let Ok(id) = アセットID::生成する(名前) else {
        panic!("試験用IDを生成できなかった");
    };
    カタログ.詳細を登録する(
        id,
        PathBuf::from(format!("{名前}.blitzasset")),
        vec![PathBuf::from(format!("assets/{名前}.glb"))],
        アセットメタデータ {
            頂点数,
            インデックス数,
            テクスチャ格納バイト数,
            個体数: 0,
            高さ場の標本数: 高さ場の標本数::生成する(9),
        },
    );
}
