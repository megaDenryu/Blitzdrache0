//! 描画対象が持つ形状。1つのメッシュで描く対象、詳細段ごとのメッシュ列から1段を選んで描く地形、
//! 1つの原型を非空の配置列で多数描くインスタンス群を判別共用体で表す。
//! 地形とインスタンス群を別のアセット種別にせず同じシーンの中で判別するのは、カタログ解決・読込器・完了キュー・描画束を二重化しないためである。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「地形の表現」、`_doc/設計/植生インスタンスと物量計測.md`「インスタンス群の表現」

use super::instance::インスタンス群;
use super::mesh_data::メッシュデータ;
use super::skin_vertex_attribute::スキン頂点属性;
use super::terrain_lod_meshes::地形LODメッシュ群;

#[derive(Debug, Clone, PartialEq)]
pub enum 描画形状 {
    通常メッシュ(メッシュデータ),
    地形LODメッシュ群(地形LODメッシュ群),
    インスタンス群(インスタンス群),
}

impl 描画形状 {
    /// 最も詳細な幾何。スキニングの入力にする。
    /// 段の選択そのものはこの層に無い。全段を読込時にGPUへ載せるため、どの段を描くかを選ぶのはGPU資源を持つレンダラーだけである。
    pub fn 最詳細メッシュ(&self) -> &メッシュデータ {
        match self {
            Self::通常メッシュ(メッシュ) => メッシュ,
            Self::地形LODメッシュ群(群) => 群.最詳細メッシュ(),
            Self::インスタンス群(群) => 群.原型().最詳細メッシュ(),
        }
    }

    /// この形状が持つ全メッシュ。容量メタデータは全段をGPUへ載せるため、この一覧を数える。
    pub fn 全メッシュ(&self) -> &[メッシュデータ] {
        match self {
            Self::通常メッシュ(メッシュ) => std::slice::from_ref(メッシュ),
            Self::地形LODメッシュ群(群) => 群.段一覧(),
            Self::インスタンス群(群) => 群.原型().段一覧(),
        }
    }

    /// この形状が1つの段につき描く個体の数。インスタンス群だけが1より大きい値を返す。
    pub fn 個体数(&self) -> usize {
        match self {
            Self::通常メッシュ(_) | Self::地形LODメッシュ群(_) => 1,
            Self::インスタンス群(群) => 群.個体数(),
        }
    }

    /// スキン頂点属性。地形とインスタンス群はスキンを持たないため常に`None`である。
    pub fn スキン頂点属性一覧(&self) -> Option<&Vec<スキン頂点属性>> {
        match self {
            Self::通常メッシュ(メッシュ) => メッシュ.スキン頂点属性一覧.as_ref(),
            Self::地形LODメッシュ群(_) | Self::インスタンス群(_) => None,
        }
    }
}
