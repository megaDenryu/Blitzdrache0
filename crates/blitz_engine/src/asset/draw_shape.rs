//! 描画対象が持つ形状。1つのメッシュで描く対象と、詳細段ごとのメッシュ列から1段を選んで描く地形とを判別共用体で表す。
//! 地形を別のアセット種別にせず同じシーンの中で判別するのは、カタログ解決・読込器・完了キュー・描画束を二重化しないためである。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「地形の表現」

use blitz_render::地形詳細段;

use super::mesh_data::メッシュデータ;
use super::skin_vertex_attribute::スキン頂点属性;
use super::terrain_lod_meshes::地形LODメッシュ群;

#[derive(Debug, Clone, PartialEq)]
pub enum 描画形状 {
    通常メッシュ(メッシュデータ),
    地形LODメッシュ群(地形LODメッシュ群),
}

impl 描画形状 {
    /// 最も詳細な幾何。スキニングと容量見積の基準にする。
    pub fn 最詳細メッシュ(&self) -> &メッシュデータ {
        match self {
            Self::通常メッシュ(メッシュ) => メッシュ,
            Self::地形LODメッシュ群(群) => 群.最詳細メッシュ(),
        }
    }

    /// 要求された段で描く幾何。通常メッシュは段を1つしか持たないため常に同じメッシュを返す。
    pub fn 段を引く(&self, 段: 地形詳細段) -> &メッシュデータ {
        match self {
            Self::通常メッシュ(メッシュ) => メッシュ,
            Self::地形LODメッシュ群(群) => 群.段を引く(段),
        }
    }

    /// この形状が持つ全メッシュ。容量メタデータは全段をGPUへ載せるため、この一覧を数える。
    pub fn 全メッシュ(&self) -> &[メッシュデータ] {
        match self {
            Self::通常メッシュ(メッシュ) => std::slice::from_ref(メッシュ),
            Self::地形LODメッシュ群(群) => 群.段一覧(),
        }
    }

    /// スキン頂点属性。地形はスキンを持たないため常に`None`である。
    pub fn スキン頂点属性一覧(&self) -> Option<&Vec<スキン頂点属性>> {
        match self {
            Self::通常メッシュ(メッシュ) => メッシュ.スキン頂点属性一覧.as_ref(),
            Self::地形LODメッシュ群(_) => None,
        }
    }
}
