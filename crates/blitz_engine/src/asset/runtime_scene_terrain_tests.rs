//! 版2の地形形状に対する読取境界の検査。地形はスキニングの対象にしないため、スキン頂点属性を持つ段を含むバイト列を読取が型付きエラーで拒否することを確かめる。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「地形の表現」

