//! NORMAL欠如頂点の面積重みスムース法線計算(判断46)。頂点分割(glTF仕様の厳密解)は
//! インデックス構造を壊しスキンメッシュに不利なため採らず、既存の頂点共有構造を保った
//! まま計算する。各三角形の(正規化前の)外積を隣接する3頂点へ加算する。外積の大きさは
//! 三角形面積に比例するため、これが自然な面積重み平均になる。

use super::vector_math::{外積, 正規化する, 引く, 足す};

/// 退化三角形しか隣接しない頂点(法線集計がゼロベクトルになる)のフォールバック。
/// 特別な意味を持たせない既定の上向きベクトル。
const 既定法線: [f32; 3] = [0.0, 1.0, 0.0];

/// `法線一覧`は`位置一覧`と同じ長さ・同じ添字対応。`None`の要素だけ計算充填し、
/// `Some`(authored)の要素はそのまま返す。
pub(super) fn 法線を確定する(
    位置一覧: &[[f32; 3]],
    インデックス一覧: &[u32],
    法線一覧: Vec<Option<[f32; 3]>>,
) -> Vec<[f32; 3]> {
    let 計算が必要 = 法線一覧.iter().any(Option::is_none);

    let mut 集計 = vec![[0.0f32; 3]; 位置一覧.len()];
    if 計算が必要 {
        for 三角形添字 in インデックス一覧.chunks_exact(3) {
            面法線を加算する(位置一覧, 三角形添字, &mut 集計);
        }
    }

    法線一覧
        .into_iter()
        .enumerate()
        .map(|(添字, 法線)| 法線.unwrap_or_else(|| 正規化する(集計[添字], 既定法線)))
        .collect()
}

fn 面法線を加算する(位置一覧: &[[f32; 3]], 三角形添字: &[u32], 集計: &mut [[f32; 3]]) {
    let i0 = 添字をusizeへ(三角形添字[0]);
    let i1 = 添字をusizeへ(三角形添字[1]);
    let i2 = 添字をusizeへ(三角形添字[2]);

    let 辺1 = 引く(位置一覧[i1], 位置一覧[i0]);
    let 辺2 = 引く(位置一覧[i2], 位置一覧[i0]);
    let 面法線 = 外積(辺1, 辺2);

    集計[i0] = 足す(集計[i0], 面法線);
    集計[i1] = 足す(集計[i1], 面法線);
    集計[i2] = 足す(集計[i2], 面法線);
}

fn 添字をusizeへ(添字: u32) -> usize {
    match usize::try_from(添字) {
        Ok(値) => 値,
        Err(_) => panic!("頂点添字{添字}がこの環境のusize範囲を超えている(到達しないはず)"),
    }
}
