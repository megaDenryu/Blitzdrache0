//! TANGENT欠如頂点の接線構成(判断46)。法線に直交する任意の接線をw=+1で構成する。
//! 法線とワールド軸の外積を使い、法線がその軸にほぼ平行なときは別の軸へ切り替えて
//! 外積の退化(ほぼゼロベクトル)を避ける。

use super::vector_math::{外積, 内積, 正規化する};

const 基準X軸: [f32; 3] = [1.0, 0.0, 0.0];
const 基準Y軸: [f32; 3] = [0.0, 1.0, 0.0];
/// 法線とX軸の内積の絶対値がこれを超えたら(ほぼ平行なら)Y軸へ切り替える。
const X軸切替閾値: f32 = 0.9;

/// `法線一覧`は`確定済み`(NORMAL計算充填後)のものを渡す。`None`の要素だけ計算し、
/// `Some`(authored)の要素はそのまま返す。
pub(super) fn 接線を確定する(
    法線一覧: &[[f32; 3]],
    接線一覧: Vec<Option<[f32; 4]>>,
) -> Vec<[f32; 4]> {
    接線一覧
        .into_iter()
        .enumerate()
        .map(|(添字, 接線)| 接線.unwrap_or_else(|| 任意の接線を作る(法線一覧[添字])))
        .collect()
}

fn 任意の接線を作る(法線: [f32; 3]) -> [f32; 4] {
    let 基準軸 = if 内積(法線, 基準X軸).abs() < X軸切替閾値 {
        基準X軸
    } else {
        基準Y軸
    };
    let 接線ベクトル = 正規化する(外積(基準軸, 法線), 基準Y軸);
    [接線ベクトル[0], 接線ベクトル[1], 接線ベクトル[2], 1.0]
}
