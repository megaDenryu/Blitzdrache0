//! 法線/接線の計算充填(判断46)で使う最小限のベクトル演算。glamはblitz_math内部限定の
//! ため、アセット読込境界のこの生ジオメトリ処理では[f32; 3]算術のみを使う。

pub(super) fn 引く(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    [a[0] - b[0], a[1] - b[1], a[2] - b[2]]
}

pub(super) fn 足す(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    [a[0] + b[0], a[1] + b[1], a[2] + b[2]]
}

pub(super) fn 外積(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    [
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    ]
}

pub(super) fn 内積(a: [f32; 3], b: [f32; 3]) -> f32 {
    a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
}

/// 長さがほぼゼロ(退化)なら`既定`を返す。0除算・NaN伝播を避けるためのフォールバック。
pub(super) fn 正規化する(ベクトル: [f32; 3], 既定: [f32; 3]) -> [f32; 3] {
    let 長さ二乗 = 内積(ベクトル, ベクトル);
    if 長さ二乗 <= f32::EPSILON {
        return 既定;
    }
    let 長さ = 長さ二乗.sqrt();
    [ベクトル[0] / 長さ, ベクトル[1] / 長さ, ベクトル[2] / 長さ]
}
