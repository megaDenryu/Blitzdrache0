//! 格納済みテクスチャ: 実行時形式が運ぶ形のテクスチャである。原寸の幅と高さ、テクスチャ格納形式、段0から順に並べた縮小段ごとのバイト列を持つ。
//! 復号済みのRGBA8を持つ`テクスチャデータ`とは別の型であり、焼く側が段を作り終えて符号化した後の値をこの型が運ぶ。
//! 生成の時点で段の並びを検査するため、この型の値を持てた時点でその並びは形式の契約を満たしている。
//! 参照: `_doc/設計/アセット実行時形式.md`「シーン内容の版5」

use super::format::テクスチャ格納形式;
use super::level_sequence_check::縮小段の並びを検査する;
use super::stored_texture_error::格納済みテクスチャエラー;
use crate::asset::texture_data::テクスチャデータ;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 格納済みテクスチャ {
    幅: u32,
    高さ: u32,
    格納形式: テクスチャ格納形式,
    段ごとのバイト列: Vec<Vec<u8>>,
}

impl 格納済みテクスチャ {
    pub fn 生成する(
        幅: u32,
        高さ: u32,
        格納形式: テクスチャ格納形式,
        段ごとのバイト列: Vec<Vec<u8>>,
    ) -> Result<Self, 格納済みテクスチャエラー> {
        縮小段の並びを検査する(幅, 高さ, 格納形式, &段ごとのバイト列)?;
        Ok(Self {
            幅,
            高さ,
            格納形式,
            段ごとのバイト列,
        })
    }

    /// 復号済みのRGBA8の原寸1枚を、縮小段を持たない格納形式RGBA8の値として写す。
    /// 版4までの実行時形式が運んでいたテクスチャと、ブロック圧縮を選ばない方針で焼いたテクスチャがこの形になる。
    pub fn rgba8の原寸から生成する(原寸: &テクスチャデータ) -> Result<Self, 格納済みテクスチャエラー> {
        Self::生成する(原寸.幅, 原寸.高さ, テクスチャ格納形式::RGBA8, vec![原寸.rgba8.clone()])
    }

    pub fn 幅を返す(&self) -> u32 {
        self.幅
    }

    pub fn 高さを返す(&self) -> u32 {
        self.高さ
    }

    pub fn 格納形式を返す(&self) -> テクスチャ格納形式 {
        self.格納形式
    }

    pub fn 段ごとのバイト列を返す(&self) -> &[Vec<u8>] {
        &self.段ごとのバイト列
    }

    /// 格納形式がRGBA8のときだけ原寸の画素列を返す。ブロック圧縮の値を復号するのはGPUであり、
    /// CPUの側に画素として読める列は存在しないため、形式ごとに返せるかどうかが変わる。
    pub fn rgba8の原寸の画素列を返す(&self) -> Option<&[u8]> {
        match self.格納形式 {
            テクスチャ格納形式::RGBA8 => self.段ごとのバイト列.first().map(Vec::as_slice),
            テクスチャ格納形式::BC1 => None,
        }
    }
}
