//! テクスチャ格納形式の算術の検査。段の寸法が4の倍数でないときのブロック数の切り上げと、
//! 零の寸法を拒むことと、形式ごとのバイト数の数え方を固定する。

#![allow(clippy::unwrap_used)]

use super::block_grid::ブロック格子;
use super::byte_error::テクスチャ格納バイト数エラー;
use super::format::テクスチャ格納形式;

#[test]
fn ブロック数は4で切り上げて割る() {
    let 格子 = ブロック格子::生成する(5, 3).unwrap();
    assert_eq!(格子.横のブロック数を返す(), 2);
    assert_eq!(格子.縦のブロック数を返す(), 1);
    assert_eq!(格子.総ブロック数を返す(), 2);
}

#[test]
fn 一辺の倍数の段はブロック数がちょうど割り切れる() {
    let 格子 = ブロック格子::生成する(8, 4).unwrap();
    assert_eq!(格子.横のブロック数を返す(), 2);
    assert_eq!(格子.縦のブロック数を返す(), 1);
}

#[test]
fn 最小の段も1ブロックを持つ() {
    let 格子 = ブロック格子::生成する(1, 1).unwrap();
    assert_eq!(格子.総ブロック数を返す(), 1);
}

#[test]
fn 零の寸法の段は拒む() {
    assert_eq!(
        ブロック格子::生成する(0, 4),
        Err(テクスチャ格納バイト数エラー::縮小段の寸法が零 { 幅: 0, 高さ: 4 })
    );
    assert_eq!(
        テクスチャ格納形式::RGBA8.縮小段の格納バイト数を求める(4, 0),
        Err(テクスチャ格納バイト数エラー::縮小段の寸法が零 { 幅: 4, 高さ: 0 })
    );
}

#[test]
fn rgba8の段のバイト数は画素数の4倍() {
    assert_eq!(テクスチャ格納形式::RGBA8.縮小段の格納バイト数を求める(5, 5), Ok(100));
    assert_eq!(テクスチャ格納形式::RGBA8.縮小段の格納バイト数を求める(1, 1), Ok(4));
}

#[test]
fn bc1の段のバイト数はブロック数の8倍() {
    assert_eq!(テクスチャ格納形式::BC1.縮小段の格納バイト数を求める(5, 5), Ok(32));
    assert_eq!(テクスチャ格納形式::BC1.縮小段の格納バイト数を求める(4, 4), Ok(8));
    assert_eq!(テクスチャ格納形式::BC1.縮小段の格納バイト数を求める(1, 1), Ok(8));
    assert_eq!(テクスチャ格納形式::BC1.縮小段の格納バイト数を求める(256, 256), Ok(32768));
}

#[test]
fn bc1は非圧縮の8分の1のバイト数になる() {
    let 非圧縮 = テクスチャ格納形式::RGBA8.縮小段の格納バイト数を求める(256, 256).unwrap();
    let 圧縮 = テクスチャ格納形式::BC1.縮小段の格納バイト数を求める(256, 256).unwrap();
    assert_eq!(非圧縮 / 8, 圧縮);
}

#[test]
fn 表現できないバイト数は拒む() {
    assert_eq!(
        テクスチャ格納形式::RGBA8.縮小段の格納バイト数を求める(u32::MAX, u32::MAX),
        Err(テクスチャ格納バイト数エラー::格納バイト数が64ビットで表せない {
            幅: u32::MAX,
            高さ: u32::MAX,
        })
    );
}
