//! 格納済みテクスチャの生成が受理する並びと拒む並びの検査。

#![allow(clippy::unwrap_used)]

use super::level_extent::縮小段の寸法;
use super::stored_texture::格納済みテクスチャ;
use super::stored_texture_error::格納済みテクスチャエラー;
use super::テクスチャ格納形式;
use crate::asset::texture_data::テクスチャデータ;

fn bc1の全段を作る(幅: u32, 高さ: u32) -> Vec<Vec<u8>> {
    let 原寸 = 縮小段の寸法::生成する(幅, 高さ).unwrap();
    (0..原寸.縮小段数の上限を返す())
        .map(|段番号| {
            let 長さ = テクスチャ格納形式::BC1
                .縮小段の格納バイト数を求める(原寸.縮小段番号が指す寸法(段番号))
                .unwrap();
            vec![0; usize::try_from(長さ).unwrap()]
        })
        .collect()
}

#[test]
fn 段番号が増えるごとに寸法が半分になり1で止まる() {
    let 原寸 = 縮小段の寸法::生成する(8, 5).unwrap();
    assert_eq!(原寸.縮小段番号が指す寸法(0), 原寸);
    assert_eq!(原寸.縮小段番号が指す寸法(1), 縮小段の寸法::生成する(4, 2).unwrap());
    assert_eq!(原寸.縮小段番号が指す寸法(3), 縮小段の寸法::生成する(1, 1).unwrap());
    assert_eq!(原寸.縮小段数の上限を返す(), 4);
    assert_eq!(縮小段の寸法::生成する(1, 1).unwrap().縮小段数の上限を返す(), 1);
}

#[test]
fn rgba8の原寸を1段の格納済みテクスチャへ写す() {
    let 原寸 = テクスチャデータ {
        幅: 2,
        高さ: 1,
        rgba8: vec![1, 2, 3, 255, 4, 5, 6, 255],
    };
    let 格納済み = 格納済みテクスチャ::rgba8の原寸から生成する(&原寸).unwrap();
    assert_eq!(格納済み.格納形式を返す(), テクスチャ格納形式::RGBA8);
    assert_eq!(格納済み.段ごとのバイト列を返す().len(), 1);
    assert_eq!(格納済み.rgba8の原寸の画素列を返す(), Some(原寸.rgba8.as_slice()));
}

#[test]
fn rgba8が2段以上を持つ並びを拒む() {
    let 誤り = 格納済みテクスチャ::生成する(2, 1, テクスチャ格納形式::RGBA8, vec![vec![0; 8], vec![0; 4]]);
    assert_eq!(誤り, Err(格納済みテクスチャエラー::RGBA8が縮小段を持つ { 縮小段数: 2 }));
}

#[test]
fn bc1の全段を受理し画素列を返さない() {
    let 格納済み = 格納済みテクスチャ::生成する(8, 8, テクスチャ格納形式::BC1, bc1の全段を作る(8, 8)).unwrap();
    assert_eq!(格納済み.段ごとのバイト列を返す().len(), 4);
    assert_eq!(格納済み.幅を返す(), 8);
    assert_eq!(格納済み.高さを返す(), 8);
    assert_eq!(格納済み.rgba8の原寸の画素列を返す(), None);
}

#[test]
fn 段のバイト数が算術と食い違う並びを拒む() {
    let mut 全段 = bc1の全段を作る(8, 8);
    全段[1].push(0);
    let 誤り = 格納済みテクスチャ::生成する(8, 8, テクスチャ格納形式::BC1, 全段);
    assert_eq!(
        誤り,
        Err(格納済みテクスチャエラー::縮小段のバイト数不一致 {
            段番号: 1,
            期待長: 8,
            実長: 9
        })
    );
}

#[test]
fn 段の本数が上限を超える並びと空の並びを拒む() {
    let mut 全段 = bc1の全段を作る(8, 8);
    全段.push(vec![0; 8]);
    assert_eq!(
        格納済みテクスチャ::生成する(8, 8, テクスチャ格納形式::BC1, 全段),
        Err(格納済みテクスチャエラー::縮小段数が上限を超える { 縮小段数: 5, 上限: 4 })
    );
    assert_eq!(
        格納済みテクスチャ::生成する(8, 8, テクスチャ格納形式::BC1, Vec::new()),
        Err(格納済みテクスチャエラー::縮小段が1本も無い)
    );
}
