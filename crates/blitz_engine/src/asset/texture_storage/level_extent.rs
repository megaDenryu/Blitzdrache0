//! 縮小段の寸法の算術。原寸の幅と高さと段番号からその段の幅と高さを求める工程と、原寸が持てる縮小段の本数の上限を求める工程を持つ。
//! 段は前の段を切り捨てで半分にした寸法であり、1になった軸は1のまま残るため、段番号ぶんの右シフトと1への切り上げで求まる。
//! 焼く側が並べた段の連なりと、読む側が段ごとに数える期待バイト数が同じ寸法を指すように、この算術をCPU正本として1つに置く。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`

use super::byte_error::テクスチャ格納バイト数エラー;

/// 寸法を表す整数のビット数。u32の右シフトはこの数以上で定義されないため、段番号がここへ届いた時点で寸法は1に落ちている。
const 寸法のビット数: u32 = 32;

pub fn 縮小段の幅と高さを求める(
    原寸の幅: u32,
    原寸の高さ: u32,
    段番号: u32,
) -> Result<(u32, u32), テクスチャ格納バイト数エラー> {
    零の寸法を拒む(原寸の幅, 原寸の高さ)?;
    Ok((半分にする回数だけ縮める(原寸の幅, 段番号), 半分にする回数だけ縮める(原寸の高さ, 段番号)))
}

/// 原寸から1x1まで並べたときの段の本数である。幅と高さの大きい方が1になるまで半分にした回数に1を足した数と等しい。
pub fn 縮小段数の上限を求める(原寸の幅: u32, 原寸の高さ: u32) -> Result<u32, テクスチャ格納バイト数エラー> {
    零の寸法を拒む(原寸の幅, 原寸の高さ)?;
    Ok(寸法のビット数 - 原寸の幅.max(原寸の高さ).leading_zeros())
}

fn 半分にする回数だけ縮める(原寸: u32, 段番号: u32) -> u32 {
    if 段番号 >= 寸法のビット数 {
        return 1;
    }
    (原寸 >> 段番号).max(1)
}

fn 零の寸法を拒む(幅: u32, 高さ: u32) -> Result<(), テクスチャ格納バイト数エラー> {
    if 幅 == 0 || 高さ == 0 {
        return Err(テクスチャ格納バイト数エラー::縮小段の寸法が零 { 幅, 高さ });
    }
    Ok(())
}
