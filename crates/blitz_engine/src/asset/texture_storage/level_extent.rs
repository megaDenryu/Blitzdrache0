//! 縮小段の寸法: 縮小段1段の幅と高さを組で持つ値オブジェクトと、原寸から段の寸法と段の本数を導く算術。
//! 段は前の段を切り捨てで半分にした寸法であり、1になった軸は1のまま残るため、段番号ぶんの右シフトと1への切り上げで求まる。
//! 焼く側が並べた段の連なりと、読む側が段ごとに数える期待バイト数が同じ寸法を指すように、この算術をCPU正本として1つに置く。
//!
//! 幅と高さを組で持つのは、2つの数を裸で並べると呼び出しの側で取り違えても署名が通り、求めた段の寸法を
//! 無名のタプルで返すと受け取り側が並び順を記憶することになるためである。零の軸を拒む検査も、この型の
//! 構築の口へ集めることで、段の寸法を受け取る側が同じ検査を書き直さずに済む。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`

use super::byte_error::テクスチャ格納バイト数エラー;

/// 寸法を表す整数のビット数。u32の右シフトはこの数以上で定義されないため、段番号がここへ届いた時点で寸法は1に落ちている。
const 寸法のビット数: u32 = 32;

/// 縮小段1段の幅と高さ。原寸も段0の寸法としてこの型で表す。
/// 不変条件: 幅も高さも1以上である。縮小段の連なりは1x1で止まるため、零の軸を持つ段はどの形式にも存在しない。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 縮小段の寸法 {
    幅: u32,
    高さ: u32,
}

impl 縮小段の寸法 {
    pub fn 生成する(幅: u32, 高さ: u32) -> Result<Self, テクスチャ格納バイト数エラー> {
        if 幅 == 0 || 高さ == 0 {
            return Err(テクスチャ格納バイト数エラー::縮小段の寸法が零 { 幅, 高さ });
        }
        Ok(Self { 幅, 高さ })
    }

    pub fn 幅を返す(self) -> u32 {
        self.幅
    }

    pub fn 高さを返す(self) -> u32 {
        self.高さ
    }

    /// この寸法を原寸としたときの、その段番号の段の寸法。どちらの軸も1未満へは落ちないため不変条件は保たれる。
    pub fn 縮小段番号が指す寸法(self, 段番号: u32) -> Self {
        Self {
            幅: 半分にする回数だけ縮める(self.幅, 段番号),
            高さ: 半分にする回数だけ縮める(self.高さ, 段番号),
        }
    }

    /// この寸法を原寸として1x1まで並べたときの段の本数である。幅と高さの大きい方が1になるまで半分にした回数に1を足した数と等しい。
    pub fn 縮小段数の上限を返す(self) -> u32 {
        寸法のビット数 - self.幅.max(self.高さ).leading_zeros()
    }
}

fn 半分にする回数だけ縮める(原寸: u32, 段番号: u32) -> u32 {
    if 段番号 >= 寸法のビット数 {
        return 1;
    }
    (原寸 >> 段番号).max(1)
}
