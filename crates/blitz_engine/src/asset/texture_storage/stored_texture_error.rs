//! 格納済みテクスチャの生成と復元が拒む状態。焼く側と読む側が同じ検査を通るため、拒む理由もこの1つの型に集める。
//! バイト列から復元できない理由(宣言長の食い違い・寸法0・未知の格納形式)も同じ型が持つ。復元できない状態と
//! 生成できない状態を2つの型へ分けると、テクスチャ1件を読む工程が2つの語彙を混ぜて返すことになるためである。
//! 参照: `_doc/設計/アセット実行時形式.md`「シーン内容の版5」

use thiserror::Error;

use super::byte_error::テクスチャ格納バイト数エラー;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 格納済みテクスチャエラー {
    #[error("テクスチャが縮小段を1本も持たない")]
    縮小段が1本も無い,
    #[error("格納形式RGBA8のテクスチャが縮小段を{縮小段数}本持つ")]
    RGBA8が縮小段を持つ { 縮小段数: u32 }, // 実行時が段を作るためファイルが持つとGPU上で二重になる
    #[error("縮小段の本数{縮小段数}が原寸から作れる本数{上限}を超える")]
    縮小段数が上限を超える { 縮小段数: u32, 上限: u32 },
    #[error("縮小段{段番号}の期待バイト数{期待長}と実長{実長}が一致しない")]
    縮小段のバイト数不一致 { 段番号: u32, 期待長: u64, 実長: u64 },
    #[error("縮小段の本数を32ビットで表せない")]
    縮小段数が32ビットで表せない,
    #[error("縮小段{段番号}のバイト数を64ビットで表せない")]
    縮小段のバイト数が64ビットで表せない { 段番号: u32 },
    #[error("縮小段の格納バイト数を求められない: {0}")]
    格納バイト数の算術失敗(#[from] テクスチャ格納バイト数エラー),
    #[error("テクスチャの宣言RGBA8長{期待長}バイトと実長{実長}バイトが一致しない")]
    宣言長と実長が一致しない { 期待長: u64, 実長: u64 },
    #[error("テクスチャの幅と高さは1以上でなければならない")]
    寸法が0である,
    #[error("未知のテクスチャ格納形式の判別値だった: {0}")]
    未知の格納形式の判別値(u8),
}
