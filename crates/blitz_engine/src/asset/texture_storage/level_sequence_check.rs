//! 縮小段の並びを検査する工程。受け取るのは原寸の幅と高さとテクスチャ格納形式と段ごとのバイト列、返すのは受理か型付きエラーである。
//! 見るのは4つである。段が1本以上あること、格納形式RGBA8が縮小段を持たないこと、段の本数が原寸から作れる本数を超えないこと、
//! 段ごとのバイト数が格納形式の算術と一致することである。
//! RGBA8の縮小段を拒むのは、その形式の段を実行時の縮小段の生成が作るためであり、ファイルが持つ段と実行時が作る段の二重を許さないためである。
//! 参照: `_doc/設計/アセット実行時形式.md`「シーン内容の版5」

use super::format::テクスチャ格納形式;
use super::level_extent::縮小段の寸法;
use super::stored_texture_error::格納済みテクスチャエラー;

pub(super) fn 縮小段の並びを検査する(
    幅: u32,
    高さ: u32,
    格納形式: テクスチャ格納形式,
    段ごとのバイト列: &[Vec<u8>],
) -> Result<(), 格納済みテクスチャエラー> {
    let 縮小段数 =
        u32::try_from(段ごとのバイト列.len()).map_err(|_| 格納済みテクスチャエラー::縮小段数が32ビットで表せない)?;
    if 縮小段数 == 0 {
        return Err(格納済みテクスチャエラー::縮小段が1本も無い);
    }
    if 格納形式 == テクスチャ格納形式::RGBA8 && 縮小段数 > 1 {
        return Err(格納済みテクスチャエラー::RGBA8が縮小段を持つ { 縮小段数 });
    }
    let 原寸 = 縮小段の寸法::生成する(幅, 高さ)?;
    let 上限 = 原寸.縮小段数の上限を返す();
    if 縮小段数 > 上限 {
        return Err(格納済みテクスチャエラー::縮小段数が上限を超える { 縮小段数, 上限 });
    }
    for (添字, バイト列) in 段ごとのバイト列.iter().enumerate() {
        let 段番号 = u32::try_from(添字).map_err(|_| 格納済みテクスチャエラー::縮小段数が32ビットで表せない)?;
        段のバイト数を照合する(原寸, 格納形式, 段番号, バイト列.len())?;
    }
    Ok(())
}

fn 段のバイト数を照合する(
    原寸: 縮小段の寸法,
    格納形式: テクスチャ格納形式,
    段番号: u32,
    実長: usize,
) -> Result<(), 格納済みテクスチャエラー> {
    let 期待長 = 格納形式.縮小段の格納バイト数を求める(原寸.縮小段番号が指す寸法(段番号))?;
    let 実長 =
        u64::try_from(実長).map_err(|_| 格納済みテクスチャエラー::縮小段のバイト数が64ビットで表せない { 段番号 })?;
    if 期待長 == 実長 {
        return Ok(());
    }
    Err(格納済みテクスチャエラー::縮小段のバイト数不一致 {
        段番号, 期待長, 実長
    })
}
