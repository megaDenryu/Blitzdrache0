//! ブロック格子: 縮小段1段の画素をブロック圧縮の4x4ブロックへ区切った格子である。
//! 段の幅と高さが4の倍数でないときブロックの側は端の画素を複製した余白を持つため、
//! ブロックの個数は段の画素数からは導けない。その個数をこの型が持つ。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`

use super::level_extent::縮小段の寸法;

/// ブロック圧縮の族はどの形式も4x4の画素を1ブロックにする。
pub const ブロックの一辺の画素数: u32 = 4;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ブロック格子 {
    横のブロック数: u32,
    縦のブロック数: u32,
}

impl ブロック格子 {
    /// 段の幅と高さをブロックの一辺で切り上げて割った個数を持つ。零の軸を拒むのは寸法の型の構築であり、ここには現れない。
    pub fn 生成する(段の寸法: 縮小段の寸法) -> Self {
        Self {
            横のブロック数: 段の寸法.幅を返す().div_ceil(ブロックの一辺の画素数),
            縦のブロック数: 段の寸法.高さを返す().div_ceil(ブロックの一辺の画素数),
        }
    }

    pub fn 横のブロック数を返す(self) -> u32 {
        self.横のブロック数
    }

    pub fn 縦のブロック数を返す(self) -> u32 {
        self.縦のブロック数
    }

    /// 32ビットの個数どうしの積は32ビットに収まらないため64ビットで返す。
    pub fn 総ブロック数を返す(self) -> u64 {
        u64::from(self.横のブロック数) * u64::from(self.縦のブロック数)
    }
}
