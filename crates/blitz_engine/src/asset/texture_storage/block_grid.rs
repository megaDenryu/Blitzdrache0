//! ブロック格子: 縮小段1段の画素をブロック圧縮の4x4ブロックへ区切った格子である。
//! 段の幅と高さが4の倍数でないときブロックの側は端の画素を複製した余白を持つため、
//! ブロックの個数は段の画素数からは導けない。その個数をこの型が持つ。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`

use super::byte_error::テクスチャ格納バイト数エラー;

/// ブロック圧縮の族はどの形式も4x4の画素を1ブロックにする。
pub const ブロックの一辺の画素数: u32 = 4;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ブロック格子 {
    横のブロック数: u32,
    縦のブロック数: u32,
}

impl ブロック格子 {
    /// 段の幅と高さをブロックの一辺で切り上げて割った個数を持つ。零の寸法の段は存在しないため拒む。
    pub fn 生成する(段の幅: u32, 段の高さ: u32) -> Result<Self, テクスチャ格納バイト数エラー> {
        if 段の幅 == 0 || 段の高さ == 0 {
            return Err(テクスチャ格納バイト数エラー::縮小段の寸法が零 {
                幅: 段の幅, 高さ: 段の高さ
            });
        }
        Ok(Self {
            横のブロック数: 段の幅.div_ceil(ブロックの一辺の画素数),
            縦のブロック数: 段の高さ.div_ceil(ブロックの一辺の画素数),
        })
    }

    pub fn 横のブロック数を返す(self) -> u32 {
        self.横のブロック数
    }

    pub fn 縦のブロック数を返す(self) -> u32 {
        self.縦のブロック数
    }

    /// 32ビットの個数どうしの積は32ビットに収まらないため64ビットで返す。
    pub fn 総ブロック数を返す(self) -> u64 {
        u64::from(self.横のブロック数) * u64::from(self.縦のブロック数)
    }
}
