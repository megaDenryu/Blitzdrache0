//! テクスチャ格納バイト数エラー: 縮小段1段の格納バイト数を求める算術が拒む状態。
//! 焼く側と読む側が同じ算術を使うため、拒む理由もこの1つの型に集める。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`

use thiserror::Error;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum テクスチャ格納バイト数エラー {
    /// 縮小段の連なりは1x1で止まるため、幅または高さが零の段はどの形式でも存在しない。
    #[error("縮小段の幅または高さが零である: 幅{幅} 高さ{高さ}")]
    縮小段の寸法が零 { 幅: u32, 高さ: u32 },
    #[error("縮小段の格納バイト数が64ビットで表せない: 幅{幅} 高さ{高さ}")]
    格納バイト数が64ビットで表せない { 幅: u32, 高さ: u32 },
}
