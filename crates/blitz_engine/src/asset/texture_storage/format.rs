//! テクスチャ格納形式: 実行時形式がテクスチャの画素をどの符号化で運ぶかの宣言のCPU正本と、
//! 縮小段1段の格納バイト数を求める算術。焼く側と読む側の両方がこの1つの算術で段のバイト長を検査するため、
//! 形式の枝と算術を同じ場所に置く。Vulkanの画像形式への写像はblitz_render側が持ち、ここには現れない。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`

use super::block_grid::ブロック格子;
use super::byte_error::テクスチャ格納バイト数エラー;

/// 非圧縮の1画素は赤・緑・青・不透明度の4バイトである。
pub const RGBA8の1画素のバイト数: u64 = 4;

/// BC1の1ブロックはRGB565の端点2つ(4バイト)と16画素の2ビットの索引(4バイト)である。
pub const BC1の1ブロックのバイト数: u64 = 8;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum テクスチャ格納形式 {
    RGBA8,
    BC1,
}

impl テクスチャ格納形式 {
    /// 縮小段1段の幅と高さから、その段がファイルとGPUで占めるバイト数を求める。
    pub fn 縮小段の格納バイト数を求める(
        self, 段の幅: u32, 段の高さ: u32
    ) -> Result<u64, テクスチャ格納バイト数エラー> {
        let 個数 = match self {
            Self::RGBA8 => 縮小段の画素数を求める(段の幅, 段の高さ)?,
            Self::BC1 => ブロック格子::生成する(段の幅, 段の高さ)?.総ブロック数を返す(),
        };
        個数.checked_mul(self.数える単位1つのバイト数を返す()).ok_or(
            テクスチャ格納バイト数エラー::格納バイト数が64ビットで表せない {
                幅: 段の幅, 高さ: 段の高さ
            },
        )
    }

    /// バイト数を数える単位はRGBA8が1画素、BC1が1ブロックである。
    fn 数える単位1つのバイト数を返す(self) -> u64 {
        match self {
            Self::RGBA8 => RGBA8の1画素のバイト数,
            Self::BC1 => BC1の1ブロックのバイト数,
        }
    }
}

/// 段の幅と高さの積。零の寸法を持つ段は存在しないため拒む。
fn 縮小段の画素数を求める(段の幅: u32, 段の高さ: u32) -> Result<u64, テクスチャ格納バイト数エラー> {
    if 段の幅 == 0 || 段の高さ == 0 {
        return Err(テクスチャ格納バイト数エラー::縮小段の寸法が零 {
            幅: 段の幅, 高さ: 段の高さ
        });
    }
    Ok(u64::from(段の幅) * u64::from(段の高さ))
}
