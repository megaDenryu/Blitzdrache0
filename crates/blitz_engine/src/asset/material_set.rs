//! 材質集合: 1つの描画対象が持つ「材質スロットID→材質」の非空な対応。
//! 原型が形とスロットの語彙を所有し、外側の描画対象がこの集合で実際の材質を与えるという責務分担を保つ。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「入力契約と実行時形式(scene v4)」

use super::material_data::マテリアルデータ;
use super::material_set_error::材質集合エラー;
use super::material_slot_assignment::材質スロット割当;
use super::material_slot_id::材質スロットID;

/// 単一材質の描画対象は、要素1件でスロット番号0の材質集合として表す。
const 単一材質のスロット番号: u32 = 0;

#[derive(Debug, Clone, PartialEq)]
pub struct 材質集合 {
    割当一覧: Vec<材質スロット割当>,
}

impl 材質集合 {
    /// スロットIDの昇順へ整列してから保持する。並びを1つに定めるのは、同じ入力から同じバイト列を書くためである。
    /// 未使用のスロットは許容し、プリミティブが参照しないスロットがあっても拒まない。
    pub fn 生成する(mut 割当一覧: Vec<材質スロット割当>) -> Result<Self, 材質集合エラー> {
        if 割当一覧.is_empty() {
            return Err(材質集合エラー::材質なし);
        }
        割当一覧.sort_by_key(|割当| 割当.スロット);
        for 組 in 割当一覧.windows(2) {
            let (前, 後) = (&組[0], &組[1]);
            if 前.スロット == 後.スロット {
                return Err(材質集合エラー::スロットID重複 {
                    番号: 前.スロット.番号を返す(),
                });
            }
        }
        Ok(Self { 割当一覧 })
    }

    /// 1材質の描画対象を要素1件の材質集合へ写す。旧版のシーンからの変換もこの関数を通る。
    pub fn 単一材質から生成する(マテリアル: マテリアルデータ) -> Self {
        Self {
            割当一覧: vec![材質スロット割当 {
                スロット: 材質スロットID::生成する(単一材質のスロット番号),
                マテリアル,
            }],
        }
    }

    pub fn 割当一覧(&self) -> &[材質スロット割当] {
        &self.割当一覧
    }

    pub fn 件数(&self) -> usize {
        self.割当一覧.len()
    }

    /// 指定のスロットに材質が無ければ`None`を返す。存在しないスロットへの参照を拒むのは呼び出し側の責任である。
    pub fn 材質を参照する(&self, スロット: 材質スロットID) -> Option<&マテリアルデータ> {
        self.割当一覧.iter().find(|割当| 割当.スロット == スロット).map(|割当| &割当.マテリアル)
    }

    /// 指定のスロットが割当一覧の何番目かを返す。無ければ`None`。
    /// 材質そのものでなく位置を返す口を置くのは、描画束が材質を複製せずに材質集合の中の位置で材質を指すためである。
    pub fn 割当添字を求める(&self, スロット: 材質スロットID) -> Option<usize> {
        self.割当一覧.iter().position(|割当| 割当.スロット == スロット)
    }

    /// 割当添字が指す材質。範囲外なら`None`。`割当添字を求める`が返した添字だけを渡す。
    pub fn 添字で材質を参照する(&self, 添字: usize) -> Option<&マテリアルデータ> {
        self.割当一覧.get(添字).map(|割当| &割当.マテリアル)
    }

    /// 材質が1件だけならその材質、2件以上なら`None`。
    /// 最小のスロットIDを無条件に選ぶ関数を置かないのは、複数材質の材質集合をどれか1つへ無言で縮退させる呼び出しを作れてしまうためである。
    /// プリミティブが参照するスロットから材質を選ぶ経路は`材質を参照する`を使う。
    pub fn 唯一の材質(&self) -> Option<&マテリアルデータ> {
        match self.割当一覧.as_slice() {
            [割当] => Some(&割当.マテリアル),
            _ => None,
        }
    }
}
