//! 値の組み合わせが群の不変条件を破るときに、生成が型付きエラーで拒否することの検査。
//! 個々の値は生成関数を通っていて形が正しいため、破れは組み合わせを見る地点でしか捕まらない。

use super::fixture::{境界を作る, 最小メッシュを作る, 配置を作る};
use crate::asset::{
    インスタンス群, インスタンス群エラー, スキン頂点属性, メッシュデータ, 原型, 境界球, 群境界, 軸平行包囲領域
};

#[test]
fn 配置列が空の群とスキン頂点属性を持つ原型段を拒否する() {
    assert_eq!(
        インスタンス群::生成する(原型::生成する(vec![最小メッシュを作る()]).unwrap(), Vec::new(), 境界を作る()),
        Err(インスタンス群エラー::配置なし)
    );
    let スキン付き = メッシュデータ {
        スキン頂点属性一覧: Some(vec![スキン頂点属性 {
            ジョイント: [0, 0, 0, 0],
            ウェイト: [1.0, 0.0, 0.0, 0.0],
        }]),
        ..最小メッシュを作る()
    };
    assert_eq!(
        原型::生成する(vec![スキン付き]),
        Err(インスタンス群エラー::原型段にスキン頂点属性がある { 段番号: 0 })
    );
}

/// 最小メッシュの唯一の頂点は(0, 1, 0)にあり、球の中心(0, 0.5, 0)から0.5メートル離れている。
/// 半径0.1の球はこの頂点を覆えないため、値の形は正しくても群としては受け取れない。
#[test]
fn 原型の頂点を覆わない境界球を拒否する() {
    let 境界 = 群境界::生成する(
        軸平行包囲領域::生成する([-1.5, -1.0, -1.5], [11.5, 2.0, 1.5]).unwrap(),
        境界球::生成する([0.0, 0.5, 0.0], 0.1).unwrap(),
    );
    assert_eq!(
        インスタンス群::生成する(原型::生成する(vec![最小メッシュを作る()]).unwrap(), vec![配置を作る(0)], 境界),
        Err(インスタンス群エラー::境界球が原型を覆わない)
    );
}

/// 配置の中心だけを囲み、半径ぶんの広がりを足していない包囲領域。半径の加算を落とす回帰がこの形になる。
#[test]
fn 個体の境界球を覆わない包囲領域を拒否する() {
    let 境界 = 群境界::生成する(
        軸平行包囲領域::生成する([0.0, 0.5, 0.0], [10.0, 0.5, 0.0]).unwrap(),
        境界球::生成する([0.0, 0.5, 0.0], 1.5).unwrap(),
    );
    assert_eq!(
        インスタンス群::生成する(
            原型::生成する(vec![最小メッシュを作る()]).unwrap(),
            (0..3).map(配置を作る).collect(),
            境界
        ),
        Err(インスタンス群エラー::包囲領域が個体を覆わない { 軸: "X" })
    );
}
