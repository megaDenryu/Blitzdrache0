//! ジョイント: スキン階層の1ノード。親添字・逆バインド行列・バインド時姿勢を持つ。

use blitz_math::{ローカル, 変換};

use super::static_trs::静的TRS;

/// `親添字`はスキンのジョイント一覧内での添字(ルートは`None`)。
///
/// 不変条件: 親の添字は自分の添字より必ず小さい(トポロジカル順。判断42)。
/// この不変条件は`スキンデータ`を組み立てるローダが保証し、ここでは検証しない。
///
/// `バインド時`はglTFノードの静的ローカル姿勢。アニメーションクリップにこの
/// ジョイントの当該成分を動かすチャンネルが無いとき、評価器が既定値として使う
/// (判断49)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ジョイント {
    pub 親添字: Option<usize>,
    pub 逆バインド行列: 変換<ローカル, ローカル>,
    pub バインド時: 静的TRS,
}
