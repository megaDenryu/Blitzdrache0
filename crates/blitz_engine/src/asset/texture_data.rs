//! テクスチャデータ: デコード済みで常にRGBA8へ正規化した画像。

/// 幅・高さとRGBA8のバイト列（1ピクセル4バイト、行優先）。
#[derive(Debug, Clone, PartialEq)]
pub struct テクスチャデータ {
    pub 幅: u32,
    pub 高さ: u32,
    pub rgba8: Vec<u8>,
}

/// ベースカラー無しメッシュ用の1x1白テクスチャ。
///
/// 注意: `シーンを読み込む` はこれを自動適用しない。呼び出し側が
/// `シーンデータ.ベースカラー` が`None`だったときに明示的に呼ぶ
/// （無言のデフォルト適用の禁止）。
pub fn 白テクスチャデータを作る() -> テクスチャデータ {
    テクスチャデータ {
        幅: 1,
        高さ: 1,
        rgba8: vec![255, 255, 255, 255],
    }
}
