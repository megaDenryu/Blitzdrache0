//! テクスチャデータ: デコード済みで常にRGBA8へ正規化した画像。

/// 幅・高さとRGBA8のバイト列（1ピクセル4バイト、行優先）。
#[derive(Debug, Clone, PartialEq)]
pub struct テクスチャデータ {
    pub 幅: u32,
    pub 高さ: u32,
    pub rgba8: Vec<u8>,
}

/// ベースカラー・metallicRoughness無しメッシュ用の1x1白テクスチャ(判断23)。
///
/// 注意: `シーンを読み込む` はこれを自動適用しない。呼び出し側が
/// `マテリアルデータ` の該当テクスチャが`None`だったときに明示的に呼ぶ
/// （無言のデフォルト適用の禁止）。metallicRoughnessの既定にも同じ白を使い、
/// 実際の値は係数(metallicFactor/roughnessFactor)側で制御する。
pub fn 白テクスチャデータを作る() -> テクスチャデータ {
    テクスチャデータ {
        幅: 1,
        高さ: 1,
        rgba8: vec![255, 255, 255, 255],
    }
}

/// 法線マップ無しメッシュ用の1x1既定法線テクスチャ(判断23)。
/// 接線空間の(0, 0, 1)(=変化なし)を8bit UNORMへ符号化した値。
pub fn 法線マップ既定テクスチャを作る() -> テクスチャデータ {
    テクスチャデータ {
        幅: 1,
        高さ: 1,
        rgba8: vec![128, 128, 255, 255],
    }
}
