//! アセット読込・デコードの型付きエラー。
//!
//! 注意: gltf/imageのエラー型は公開APIに出さない（封じ込め規約）ため、
//! すべて文字列化して包む。

use thiserror::Error;

use super::id::アセットID;

/// アセットの読込・解析・デコードで起こりうる失敗。
#[derive(Debug, Error)]
pub enum アセットエラー {
    #[error("カタログに未登録のアセットID: {0}")]
    カタログ未登録(アセットID),

    #[error("ファイル読込に失敗した: {0}")]
    ファイル読込失敗(String),

    #[error("glTFの解析に失敗した: {0}")]
    解析失敗(String),

    #[error("画像デコードに失敗した: {0}")]
    画像デコード失敗(String),

    #[error("glTFにメッシュが無い")]
    メッシュなし,

    #[error("メッシュにプリミティブが無い")]
    プリミティブなし,

    #[error("プリミティブに頂点位置(POSITION)が無い")]
    頂点位置なし,

    #[error("プリミティブに法線が無い")]
    法線なし,

    #[error("未対応のバッファ形式(data URI等)")]
    未対応バッファ形式,

    #[error("未対応の画像形式(data URI等)")]
    未対応画像形式,
}
