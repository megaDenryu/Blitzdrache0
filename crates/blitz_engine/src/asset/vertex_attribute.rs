//! メッシュ頂点属性: エンジン中立のCPU側頂点データ。GPU境界型ではないため
//! reprは不要（レンダラー側で改めてGPU境界型に変換する）。

/// 位置・法線・接線・UVを持つ1頂点分の属性(判断25: 法線マップ用に接線を追加)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct メッシュ頂点属性 {
    pub 位置: [f32; 3],
    pub 法線: [f32; 3],
    /// UVのU方向に沿った表面ベクトル。w成分は従法線の向き(±1)。
    /// glTFにTANGENT属性が無い場合は(1,0,0,1)を充填する
    /// (法線マップ無しマテリアルでは使われないため正常系)。
    pub 接線: [f32; 4],
    pub uv: [f32; 2],
}
