//! カタログ経由の実行時シーン読込で返す型付きエラー。

use super::runtime_file::実行時形式のファイルの読み取りの破れ;
use super::{id::アセットID, runtime_format::アセット実行時形式エラー};

#[derive(Debug, thiserror::Error)]
pub enum 実行時シーン読込エラー {
    #[error("カタログに未登録のアセットID: {0}")]
    カタログ未登録(アセットID),
    #[error("実行時アセットのファイル読込に失敗した: {0}")]
    ファイル読込失敗(#[from] 実行時形式のファイルの読み取りの破れ),
    #[error("実行時アセットの形式検査に失敗した: {0}")]
    形式不正(#[from] アセット実行時形式エラー),
}
