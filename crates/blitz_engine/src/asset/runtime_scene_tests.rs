/// 検査で使う原寸1x1のテクスチャを、格納形式RGBA8の格納済みテクスチャとして作る。
pub(crate) fn 原寸だけのrgba8テクスチャを作る(幅: u32, 高さ: u32, rgba8: Vec<u8>) -> 格納済みテクスチャ {
    match 格納済みテクスチャ::rgba8の原寸から生成する(&テクスチャデータ { 幅, 高さ, rgba8 }) {
        Ok(値) => 値,
        Err(誤り) => panic!("検査用のテクスチャを格納済みの形にできなかった: {誤り}"),
    }
}

#[test]
fn 静的シーンを決定的に往復する() {
    let シーン = 静的シーンを作る(vec![10, 20, 30, 255], 0.2);
    let Ok(一回目) = シーンを実行時形式へ格納する(&シーン) else {
        panic!("静的シーンを1回目の実行時形式へ格納できなかった");
    };
    let Ok(二回目) = シーンを実行時形式へ格納する(&シーン) else {
        panic!("静的シーンを2回目の実行時形式へ格納できなかった");
    };
    assert_eq!(一回目, 二回目);
    assert_eq!(実行時形式からシーンを読む(&一回目), Ok(シーン));
}

/// テクスチャの画素列の長さが寸法と食い違う値は`格納済みテクスチャ`の生成が拒むため、焼く手前に存在できない。
/// 焼いたバイト列の側の食い違いは`runtime_scene_multi_material_tests::texture_negative_tests`が読取で拒むことを確かめる。
#[test]
fn 描画対象が0件のシーンを拒否する() {
    let 正常 = 静的シーンを作る(vec![10, 20, 30, 255], 0.2);
    let Ok(mut 空内容) = シーンを実行時形式へ格納する(&正常) else {
        panic!("空シーン検査用の実行時形式を格納できなかった");
    };
    空内容[24..28].copy_from_slice(&0_u32.to_le_bytes());
    assert!(matches!(実行時形式からシーンを読む(&空内容), Err(アセット実行時形式エラー::描画対象なし)));
}

#[test]
fn 重複idと範囲外係数を拒否する() {
    let シーン = 静的シーンを作る(vec![10, 20, 30, 255], 0.2);
    let 対象 = シーン.先頭の描画対象().clone();
    let 重複 = シーンデータ::生成する(対象.clone(), vec![対象], Vec::new(), None, Vec::new());
    assert!(matches!(
        シーンを実行時形式へ格納する(&重複),
        Err(アセット実行時形式エラー::描画対象ID重複(7))
    ));

    let 係数不正 = 静的シーンを作る(vec![10, 20, 30, 255], 1.1);
    assert!(matches!(
        シーンを実行時形式へ格納する(&係数不正),
        Err(アセット実行時形式エラー::マテリアル係数範囲外)
    ));
}

