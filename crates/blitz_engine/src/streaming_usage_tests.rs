use crate::{
    GPU転送完了結果,
    streaming_ledger_tests::{候補集合を作る, 試験見積量},
    ストリーミングメモリ量, チャンク台帳, チャンク座標, チャンク状態, 準備完了結果,
};

/// 見積と異なる値を実測として与え、置き換えが起きたことを使用量から判別できるようにする。
fn 実測ramバイト数() -> u64 {
    130
}

fn 使用量(台帳: &チャンク台帳) -> ストリーミングメモリ量 {
    match 台帳.現在使用量を導出する() {
        Ok(使用量) => 使用量,
        Err(誤り) => panic!("現在使用量を導出できなかった: {誤り}"),
    }
}

#[test]
fn 状態ごとに現在使用量を導出する() {
    let 候補集合 = 候補集合を作る(0.0, 0);
    let 座標 = 候補集合[0].要求().座標();
    let 見積 = 試験見積量();
    let 実測 = 実測ramバイト数();
    let mut 台帳 = チャンク台帳::空を作る();
    assert!(台帳.必要集合を反映する(&候補集合).is_ok());
    assert_eq!(使用量(&台帳), ストリーミングメモリ量::生成する(0, 0));
    assert_eq!(台帳.読込を開始する(座標), Ok(()));
    assert_eq!(使用量(&台帳), ストリーミングメモリ量::生成する(見積.ramバイト数, 0));
    assert_eq!(台帳.準備完了を反映する(座標, 実測), Ok(準備完了結果::GPU転送待ち));
    assert_eq!(使用量(&台帳), ストリーミングメモリ量::生成する(実測, 0));
    assert_eq!(台帳.gpu転送を開始する(座標), Ok(()));
    assert_eq!(使用量(&台帳), ストリーミングメモリ量::生成する(実測, 見積.vramバイト数));
    assert_eq!(台帳.gpu転送完了を反映する(座標), Ok(GPU転送完了結果::フレーム反映待ち));
    assert_eq!(使用量(&台帳), ストリーミングメモリ量::生成する(0, 見積.vramバイト数));
    assert_eq!(台帳.フレーム境界で常駐化する(座標), Ok(()));
    assert_eq!(使用量(&台帳), ストリーミングメモリ量::生成する(0, 見積.vramバイト数));
    assert!(台帳.必要集合を反映する(&[]).is_ok());
    assert_eq!(台帳.状態を引く(座標), Some(チャンク状態::解除待ち));
    assert_eq!(使用量(&台帳), ストリーミングメモリ量::生成する(0, 見積.vramバイト数));
}

#[test]
fn 準備完了の実測が見積と異なるとき使用量は実測を反映する() {
    let 候補集合 = 候補集合を作る(0.0, 0);
    let 座標 = 候補集合[0].要求().座標();
    let 実測 = 実測ramバイト数();
    assert_ne!(実測, 試験見積量().ramバイト数);
    let mut 台帳 = チャンク台帳::空を作る();
    assert!(台帳.必要集合を反映する(&候補集合).is_ok());
    assert_eq!(台帳.読込を開始する(座標), Ok(()));
    assert_eq!(台帳.準備完了を反映する(座標, 実測), Ok(準備完了結果::GPU転送待ち));
    assert_eq!(使用量(&台帳), ストリーミングメモリ量::生成する(実測, 0));
}

#[test]
fn 異なる状態のチャンクの使用量を合算する() {
    let 候補集合 = 候補集合を作る(0.0, 1);
    let 見積 = 試験見積量();
    let 実測 = 実測ramバイト数();
    let mut 台帳 = チャンク台帳::空を作る();
    assert!(台帳.必要集合を反映する(&候補集合).is_ok());
    常駐まで進める(&mut 台帳, 候補集合[0].要求().座標(), 実測);
    準備済みまで進める(&mut 台帳, 候補集合[1].要求().座標(), 実測);
    assert_eq!(台帳.読込を開始する(候補集合[2].要求().座標()), Ok(()));
    let 期待ram = 実測 + 見積.ramバイト数;
    assert_eq!(使用量(&台帳), ストリーミングメモリ量::生成する(期待ram, 見積.vramバイト数));
}

fn 準備済みまで進める(台帳: &mut チャンク台帳, 座標: チャンク座標, 実測: u64) {
    assert_eq!(台帳.読込を開始する(座標), Ok(()));
    assert_eq!(台帳.準備完了を反映する(座標, 実測), Ok(準備完了結果::GPU転送待ち));
}

fn 常駐まで進める(台帳: &mut チャンク台帳, 座標: チャンク座標, 実測: u64) {
    準備済みまで進める(台帳, 座標, 実測);
    assert_eq!(台帳.gpu転送を開始する(座標), Ok(()));
    assert_eq!(台帳.gpu転送完了を反映する(座標), Ok(GPU転送完了結果::フレーム反映待ち));
    assert_eq!(台帳.フレーム境界で常駐化する(座標), Ok(()));
}
