use std::time::{Duration, Instant};

use crate::streaming_chunk_world_fixture::{世界を作る, 後始末する};
use crate::streaming_coordinator_fixture::{準備完了を待つ, 起動する, 進める};
use crate::{ストリーミングメモリ量, チャンク座標};

fn 上限を作る() -> ストリーミングメモリ量 {
    ストリーミングメモリ量::生成する(100_000, 100_000)
}

#[test]
fn リセットは台帳と準備済みを空にし実測記憶を残す() {
    let (パス一覧, カタログ, 目録) = 世界を作る("reset_clear", &[(0, 0), (1, 0)]);
    let mut 調停 = 起動する(目録, 上限を作る(), 1);
    let 準備完了一覧 = 準備完了を待つ(&mut 調停, &カタログ, 50.0, 2);
    assert_eq!(調停.台帳登録数(), 2);
    assert_eq!(調停.実測記憶件数(), 2);

    調停.リセットする();
    assert_eq!(調停.台帳登録数(), 0);
    // 実測記憶は読み直したときの見積精度に使うため、リセットでも転送量の累計と同じく残す。
    assert_eq!(調停.実測記憶件数(), 2);
    for 座標 in &準備完了一覧 {
        let Ok(None) = 調停.gpu転送のためにシーンデータを取り出す(*座標) else {
            panic!("リセット後に準備済みCPUデータが残っていた");
        };
    }
    後始末する(&パス一覧);
}

#[test]
fn リセット前に投入した読込の完了を破棄として数える() {
    let (パス一覧, カタログ, 目録) = 世界を作る("reset_discard", &[(0, 0), (1, 0)]);
    let mut 調停 = 起動する(目録, 上限を作る(), 1);
    assert_eq!(進める(&mut 調停, &カタログ, 50.0).読込開始一覧().len(), 2);
    調停.リセットする();

    // 目録に無い遠方へ移り、リセット前の読込を読み直さない状態で完了を受け取る。
    let 期限 = Instant::now() + Duration::from_secs(5);
    let mut 破棄累積 = Vec::new();
    while 破棄累積.len() < 2 {
        assert!(Instant::now() < 期限, "リセット前の読込完了が期限内に届かなかった");
        破棄累積.extend_from_slice(進める(&mut 調停, &カタログ, 100_050.0).cpuデータ破棄一覧());
    }
    破棄累積.sort_by_key(|座標| 座標.番号を返す());
    assert_eq!(破棄累積, [チャンク座標::生成する(0, 0), チャンク座標::生成する(1, 0)]);
    assert_eq!(調停.台帳登録数(), 0);
    assert_eq!(調停.転送量().ディスク読込件数(), 2);
    後始末する(&パス一覧);
}

#[test]
fn リセット後に同じ座標を読み直しても古い完了で停止しない() {
    let (パス一覧, カタログ, 目録) = 世界を作る("reset_reload", &[(0, 0)]);
    let mut 調停 = 起動する(目録, 上限を作る(), 1);
    assert_eq!(進める(&mut 調停, &カタログ, 50.0).読込開始一覧().len(), 1);
    // リセット直後の再読込で同じ座標へ2件の読込が並ぶ。片方の完了は台帳が読込中としていない時点で届く。
    調停.リセットする();

    let 期限 = Instant::now() + Duration::from_secs(5);
    while 調停.転送量().ディスク読込件数() < 2 {
        assert!(Instant::now() < 期限, "読み直しの完了が期限内に揃わなかった");
        進める(&mut 調停, &カタログ, 50.0);
    }
    assert_eq!(調停.台帳登録数(), 1);
    後始末する(&パス一覧);
}
