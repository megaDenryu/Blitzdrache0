//! 世界問い合わせ結果: 世界の形への問い合わせが返す、値と完全性の対である。
//!
//! 高さ場は世界に1枚だけで常にメモリへ載っているため、今のところ完全性が「評価できない領域を含む」になるのは
//! 高さ場の広がりの外へ出たときだけである。それでもこの型を高さ場の問い合わせにも使うのは、
//! チャンク由来の形(建物・散布物)の問い合わせが同じ2軸を返し、呼び出し側が同じ形で受け取れるようにするためである。

use super::completeness::問い合わせ完全性;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 世界問い合わせ結果<値> {
    値: 値,
    完全性: 問い合わせ完全性,
}

impl<値> 世界問い合わせ結果<値> {
    pub fn 生成する(値: 値, 完全性: 問い合わせ完全性) -> Self {
        Self { 値, 完全性 }
    }

    pub fn 値(&self) -> &値 {
        &self.値
    }

    pub fn 完全性(&self) -> 問い合わせ完全性 {
        self.完全性
    }
}
