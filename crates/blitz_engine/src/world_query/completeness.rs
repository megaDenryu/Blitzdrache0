//! 問い合わせ完全性: 世界への問い合わせが返した答えが確定的か、評価できない領域のせいで確定的でないかを表す軸である。
//!
//! 当たりの値と別の軸に置くのは、「当たらなかった」と「調べられなかったので分からない」を別の事実として
//! 区別するためである。「当たった/当たらない/不明」の3値へ潰すと、この2つが同じ枝へ落ちる。
//!
//! 最初の当たりを求める問い合わせでは、当たりを見つけた答えが常に「対象範囲を完全に評価できた」になる。
//! 「確定した当たり」と「その手前の未評価」が同時に立つ状態は作れない。評価できない領域を含むが立つのは
//! 当たらなかった側だけであり、その答えは「この範囲に当たりは無い」ではなく「打ち切りより先は分からない」と読む。
//!
//! この性質が成り立つ理由は2つあり、答える側の作りで分かれる。走査の順が問い合わせの範囲に沿っている側
//! (高さ場の升目の走査)では、評価できない領域に達した時点で走査が止まるため、当たりを見つけた時点でその手前を
//! すべて評価し終えている。範囲の全体を集計して完全性を決める側(読込済みチャンクの数え上げ)では順序が無いため、
//! 当たりの手前だけを覆う範囲へ切り詰めて完全性を問い直す。切り詰めた範囲が完全ならその当たりより早い当たりは
//! 在りえず、切り詰めても完全でなければ当たりを捨てて当たらなかった側で答える。
//! 参照: `crates/blitz_engine/src/world_shape_query/truncated_confirmation.rs`
//!
//! 範囲そのものを列挙する問い合わせ(区域内の物体をすべて挙げる等)を足すときは、当たりの有無で止まらないため
//! 手前の確定した値と奥の未評価が同時に立ちうる。2軸に分けた形はその問い合わせでもそのまま使える。
//!
//! 評価できない領域には2種類ある。チャンクが未読込であることと、問い合わせが世界の形の広がりの外へ出たことである。
//! 呼び出し側がこの2つに対して取る行動は同じ(その範囲について断定しない)であるため、1つの枝で表す。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断8: 問い合わせの値と完全性を別軸にする」

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 問い合わせ完全性 {
    対象範囲を完全に評価できた, // 答えを出すのに要る範囲を実際に調べ切ったため、答えは確定的である
    評価できない領域を含む,     // 未読込の区域、または世界の形の広がりの外で止めたため、答えは確定的でない
}
