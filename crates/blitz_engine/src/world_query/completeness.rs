//! 問い合わせ完全性: 世界への問い合わせが対象範囲を完全に評価できたか、評価できない領域を含んだかを表す軸である。
//!
//! 当たりの値と別の軸に置くのは、手前の確定した当たりと奥の評価できない領域を同時に表すためである。
//! 「当たった/当たらない/不明」の3値へ潰すと、手前で確かに当たっていながら奥に未読込の区域がある場合を表せない。
//!
//! 評価できない領域には2種類ある。チャンクが未読込であることと、問い合わせが世界の形の広がりの外へ出たことである。
//! 呼び出し側がこの2つに対して取る行動は同じ(その範囲について断定しない)であるため、1つの枝で表す。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断8: 問い合わせの値と完全性を別軸にする」

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 問い合わせ完全性 {
    対象範囲を完全に評価できた, // 問い合わせた範囲のすべてを実際に調べ切った
    評価できない領域を含む,     // 未読込の区域、または世界の形の広がりの外を含んだ
}
