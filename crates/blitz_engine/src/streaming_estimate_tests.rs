use crate::{
    アセットメタデータ, ストリーミングメモリ量, ストリーミング見積エラー, チャンクメモリ量を見積もる
};

#[test]
fn 頂点とインデックスとテクスチャのバイト数を合計する() {
    let メタデータ = アセットメタデータ {
        頂点数: 3,
        インデックス数: 6,
        テクスチャバイト数: 64,
        個体数: 0,
    };
    let 期待 = 3 * 48 + 6 * 4 + 64;
    assert_eq!(チャンクメモリ量を見積もる(メタデータ), Ok(ストリーミングメモリ量::生成する(期待, 期待)));
}

#[test]
fn 容量ゼロのメタデータはゼロバイトの見積になる() {
    assert_eq!(
        チャンクメモリ量を見積もる(アセットメタデータ::default()),
        Ok(ストリーミングメモリ量::生成する(0, 0))
    );
}

#[test]
fn 頂点数の乗算オーバーフローを型付き失敗にする() {
    let メタデータ = アセットメタデータ {
        頂点数: u64::MAX,
        インデックス数: 0,
        テクスチャバイト数: 0,
        個体数: 0,
    };
    assert_eq!(チャンクメモリ量を見積もる(メタデータ), Err(ストリーミング見積エラー::バイト数超過));
}

#[test]
fn テクスチャバイト数の加算オーバーフローを型付き失敗にする() {
    let メタデータ = アセットメタデータ {
        頂点数: 1,
        インデックス数: 1,
        テクスチャバイト数: u64::MAX,
        個体数: 0,
    };
    assert_eq!(チャンクメモリ量を見積もる(メタデータ), Err(ストリーミング見積エラー::バイト数超過));
}
