//! 時刻の型が拒む入力を表す型付きエラー。

use blitz_math::単位変換エラー;
use thiserror::Error;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 時刻エラー {
    #[error("世界時刻は有限でなければならない")]
    世界時刻が非有限,
    #[error("一日の長さは有限かつ正でなければならない")]
    一日の長さが正でない,
    #[error("時間倍率は有限かつ0以上でなければならない")]
    時間倍率が負または非有限,
    #[error("一日内時刻は0以上かつ一日の長さ未満でなければならない")]
    一日内時刻が範囲外,
    #[error("一日内時刻をf32精度へ狭められなかった: {0}")]
    一日内時刻を狭められない(単位変換エラー),
}
