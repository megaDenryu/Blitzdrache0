//! ゲーム時計。世界時刻の進行・停止・倍率を1つの型が所有する。
//! 実体はコンポジションルートが1つだけ持ち、フレームごとに実時間の経過を渡す。

use blitz_math::大域秒;

use super::{世界時刻, 時刻エラー, 時間倍率};

/// 時計が進んでいるかどうか。停止を倍率0で表さないのは、停止から戻したときに元の倍率を失わないためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 時計進行状態 {
    進行中,
    停止中,
}

pub struct ゲーム時計 {
    現在時刻: 世界時刻,
    倍率: 時間倍率,
    進行状態: 時計進行状態,
}

impl ゲーム時計 {
    pub fn 生成する(初期時刻: 世界時刻, 倍率: 時間倍率) -> Self {
        Self {
            現在時刻: 初期時刻,
            倍率,
            進行状態: 時計進行状態::進行中,
        }
    }

    pub fn 現在時刻(&self) -> 世界時刻 {
        self.現在時刻
    }

    pub fn 倍率(&self) -> 時間倍率 {
        self.倍率
    }

    pub fn 進行状態(&self) -> 時計進行状態 {
        self.進行状態
    }

    /// 実時間の経過を倍率で世界時間へ写して進める。停止中は1秒も進まない。
    pub fn 進める(&mut self, 実時間の経過: 大域秒) -> Result<(), 時刻エラー> {
        let 世界時間の経過 = match self.進行状態 {
            時計進行状態::進行中 => 実時間の経過 * self.倍率.値(),
            時計進行状態::停止中 => return Ok(()),
        };
        self.現在時刻 = self.現在時刻.進めた時刻(世界時間の経過)?;
        Ok(())
    }

    pub fn 停止する(&mut self) {
        self.進行状態 = 時計進行状態::停止中;
    }

    pub fn 再開する(&mut self) {
        self.進行状態 = 時計進行状態::進行中;
    }

    pub fn 倍率を変える(&mut self, 倍率: 時間倍率) {
        self.倍率 = 倍率;
    }

    /// 任意の時刻へ飛ばす。進行と独立に時刻を選ぶ検収や、保存された世界の復元で使う。
    pub fn 時刻を設定する(&mut self, 時刻: 世界時刻) {
        self.現在時刻 = 時刻;
    }
}
