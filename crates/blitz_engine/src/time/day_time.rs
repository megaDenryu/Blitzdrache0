//! 一日の中で循環する時刻。世界時刻から導出され、天空状態の入力になる。

use blitz_math::秒;

use super::{一日の長さ, 時刻エラー};

/// 一日の始まりからの経過で表す循環時刻。周期を一緒に持つのは、位相が周期なしでは決まらないためである。
/// 不変条件: 経過は0以上であり、一日の長さ未満である。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 一日内時刻 {
    一日の始まりからの経過: 秒,
    一日の長さ: 一日の長さ,
}

impl 一日内時刻 {
    pub fn 生成する(一日の始まりからの経過: 秒, 一日の長さ: 一日の長さ) -> Result<Self, 時刻エラー> {
        let 経過 = 一日の始まりからの経過.値();
        if !経過.is_finite() || 経過 < 0.0 || 経過 >= 一日の長さ.秒数().値() {
            return Err(時刻エラー::一日内時刻が範囲外);
        }
        Ok(Self {
            一日の始まりからの経過,
            一日の長さ,
        })
    }

    pub fn 一日の始まりからの経過(&self) -> 秒 {
        self.一日の始まりからの経過
    }

    /// 一日を1とした位相。不変条件より0以上1未満になる。
    pub fn 位相(&self) -> f32 {
        self.一日の始まりからの経過.値() / self.一日の長さ.秒数().値()
    }
}
