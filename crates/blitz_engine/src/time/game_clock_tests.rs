//! ゲーム時計の進行・停止・倍率の検査。

#![allow(clippy::unwrap_used)]

use blitz_math::大域秒;

use super::{ゲーム時計, 世界時刻, 時計進行状態, 時間倍率};

fn 時計を作る(倍率: f64) -> ゲーム時計 {
    ゲーム時計::生成する(世界時刻::紀元(), 時間倍率::生成する(倍率).unwrap())
}

#[test]
fn 負または非有限の倍率は拒む() {
    assert!(時間倍率::生成する(-1.0).is_err());
    assert!(時間倍率::生成する(f64::NAN).is_err());
}

#[test]
fn 倍率のぶんだけ世界時間が進む() {
    let mut 時計 = 時計を作る(60.0);
    時計.進める(大域秒::生成する(2.0)).unwrap();
    assert_eq!(時計.現在時刻().紀元からの経過().値(), 120.0);
}

#[test]
fn 停止中は進まず再開すると再び進む() {
    let mut 時計 = 時計を作る(1.0);
    時計.停止する();
    時計.進める(大域秒::生成する(10.0)).unwrap();
    assert_eq!(時計.進行状態(), 時計進行状態::停止中);
    assert_eq!(時計.現在時刻().紀元からの経過().値(), 0.0);
    時計.再開する();
    時計.進める(大域秒::生成する(10.0)).unwrap();
    assert_eq!(時計.進行状態(), 時計進行状態::進行中);
    assert_eq!(時計.現在時刻().紀元からの経過().値(), 10.0);
}

#[test]
fn 倍率を変えると以後の進みが変わる() {
    let mut 時計 = 時計を作る(1.0);
    時計.進める(大域秒::生成する(1.0)).unwrap();
    時計.倍率を変える(時間倍率::生成する(3.0).unwrap());
    時計.進める(大域秒::生成する(1.0)).unwrap();
    assert_eq!(時計.現在時刻().紀元からの経過().値(), 4.0);
    assert_eq!(時計.倍率().値(), 3.0);
}

#[test]
fn 時刻を設定すると進行と独立に飛べる() {
    let mut 時計 = 時計を作る(1.0);
    let 目標 = 世界時刻::生成する(大域秒::生成する(-86_400.0)).unwrap();
    時計.時刻を設定する(目標);
    assert_eq!(時計.現在時刻(), 目標);
}

#[test]
fn 等速は実時間と同じ速さで進む() {
    let mut 時計 = ゲーム時計::生成する(世界時刻::紀元(), 時間倍率::等速());
    時計.進める(大域秒::生成する(7.5)).unwrap();
    assert_eq!(時計.現在時刻().紀元からの経過().値(), 7.5);
}
