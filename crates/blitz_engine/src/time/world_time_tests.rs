//! 世界時刻から一日内時刻への還元の検査。負の時刻の循環と日境界の一致を固定する。

#![allow(clippy::unwrap_used)]

use blitz_math::{大域秒, 秒};

use super::{一日の長さ, 世界時刻, 時刻エラー};

fn 時刻(秒数: f64) -> 世界時刻 {
    世界時刻::生成する(大域秒::生成する(秒数)).unwrap()
}

#[test]
fn 非有限の世界時刻は拒む() {
    assert_eq!(世界時刻::生成する(大域秒::生成する(f64::INFINITY)), Err(時刻エラー::世界時刻が非有限));
    assert_eq!(世界時刻::生成する(大域秒::生成する(f64::NAN)), Err(時刻エラー::世界時刻が非有限));
}

#[test]
fn 正でない一日の長さは拒む() {
    assert_eq!(一日の長さ::生成する(秒::生成する(0.0)), Err(時刻エラー::一日の長さが正でない));
    assert_eq!(一日の長さ::生成する(秒::生成する(-1.0)), Err(時刻エラー::一日の長さが正でない));
}

#[test]
fn 一日内時刻は日境界で循環する() {
    let 一日 = 一日の長さ::地球の一日();
    let 正午 = 時刻(43_200.0).一日内時刻へ(一日).unwrap();
    let 翌日の正午 = 時刻(43_200.0 + 86_400.0).一日内時刻へ(一日).unwrap();
    let 千日後の正午 = 時刻(43_200.0 + 86_400.0 * 1_000.0).一日内時刻へ(一日).unwrap();
    assert_eq!(正午, 翌日の正午);
    assert_eq!(正午, 千日後の正午);
}

#[test]
fn 負の世界時刻も数学的な剰余で循環する() {
    let 一日 = 一日の長さ::地球の一日();
    let 正午 = 時刻(43_200.0).一日内時刻へ(一日).unwrap();
    let 前日の正午 = 時刻(43_200.0 - 86_400.0).一日内時刻へ(一日).unwrap();
    assert_eq!(正午, 前日の正午);
    let 紀元直前 = 時刻(-1.0).一日内時刻へ(一日).unwrap();
    assert_eq!(紀元直前.一日の始まりからの経過().値(), 86_399.0);
}

#[test]
fn 位相は0以上1未満に収まる() {
    let 一日 = 一日の長さ::地球の一日();
    for 秒数 in [-86_400.5, -1e-9, 0.0, 1.0, 43_200.0, 86_399.999, 86_400.0, 1e9] {
        let 位相 = 時刻(秒数).一日内時刻へ(一日).unwrap().位相();
        assert!((0.0..1.0).contains(&位相), "秒数{秒数}の位相{位相}が0以上1未満でない");
    }
}
