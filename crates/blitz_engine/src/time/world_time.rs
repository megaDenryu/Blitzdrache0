//! 永続世界の絶対時刻。一日内時刻への還元もこの型が持つ。

use blitz_math::{大域秒, 秒};

use super::{一日の長さ, 一日内時刻, 時刻エラー};

/// 世界の紀元からの経過で表す絶対時刻。負の値は紀元より前を表す。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 世界時刻 {
    紀元からの経過: 大域秒,
}

impl 世界時刻 {
    pub fn 生成する(紀元からの経過: 大域秒) -> Result<Self, 時刻エラー> {
        if !紀元からの経過.値().is_finite() {
            return Err(時刻エラー::世界時刻が非有限);
        }
        Ok(Self { 紀元からの経過 })
    }

    pub fn 紀元() -> Self {
        Self {
            紀元からの経過: 大域秒::生成する(0.0),
        }
    }

    pub fn 紀元からの経過(&self) -> 大域秒 {
        self.紀元からの経過
    }

    /// 経過を足した時刻を返す。値オブジェクトのため自身は変えない。
    pub fn 進めた時刻(&self, 経過: 大域秒) -> Result<Self, 時刻エラー> {
        Self::生成する(self.紀元からの経過 + 経過)
    }

    /// 一日の長さで割った数学的な剰余から一日内時刻を導く。剰余を使うため負の世界時刻でも正しく循環する。
    ///
    /// 注意: f64の剰余もf32への縮小もどちらも周期そのものへ丸まりうる(負の微小値の剰余、および周期直前の値の縮小)。
    /// 周期に達した結果は一日の始まりへ畳む。畳まないと循環時刻の不変条件が破れる。
    pub fn 一日内時刻へ(&self, 一日の長さ: 一日の長さ) -> Result<一日内時刻, 時刻エラー> {
        let 周期 = f64::from(一日の長さ.秒数().値());
        let 剰余 = 大域秒::生成する(self.紀元からの経過.値().rem_euclid(周期));
        let 経過 = 剰余.秒へ狭める().map_err(時刻エラー::一日内時刻を狭められない)?;
        let 畳んだ経過 = if 経過.値() >= 一日の長さ.秒数().値() {
            秒::生成する(0.0)
        } else {
            経過
        };
        一日内時刻::生成する(畳んだ経過, 一日の長さ)
    }
}
