use crate::streaming::{チャンク目録, チャンク目録エラー, 実行時チャンク目録を読み込む};
use crate::{アセットID, チャンク座標, チャンク目録を実行時形式へ格納する};

#[test]
fn 登録した座標からアセットを参照できる() {
    let 目録 = 試験用目録();
    let Some(アセット) = 目録.アセットを参照する(チャンク座標::生成する(-2, 1)) else {
        panic!("登録した座標を参照できなかった");
    };
    assert_eq!(アセット.文字列を返す(), "chunk_x-2_z1");
    assert_eq!(目録.件数(), 2);
}

#[test]
fn 目録に無い座標は世界の端として値なしを返す() {
    let 目録 = 試験用目録();
    assert!(目録.アセットを参照する(チャンク座標::生成する(9, 9)).is_none());
    assert!(!目録.存在するか(チャンク座標::生成する(9, 9)));
}

#[test]
fn 同じ座標への二重登録を拒否する() {
    let mut 目録 = 試験用目録();
    let Ok(アセット) = アセットID::生成する("別のアセット") else {
        panic!("試験用IDを生成できなかった");
    };
    assert!(matches!(
        目録.登録する(チャンク座標::生成する(-2, 1), アセット),
        Err(チャンク目録エラー::座標重複(_))
    ));
}

#[test]
fn 実行時目録をファイル経由で復元する() {
    let Ok(バイト列) = チャンク目録を実行時形式へ格納する(&試験用目録()) else {
        panic!("試験用目録を格納できなかった");
    };
    let パス = std::env::temp_dir().join("blitz_chunk_directory_file_roundtrip.blitzchunks");
    if let Err(誤り) = std::fs::write(&パス, &バイト列) {
        panic!("試験用ファイルを書けなかった: {誤り}");
    }
    let 読込結果 = 実行時チャンク目録を読み込む(&パス);
    let _削除結果 = std::fs::remove_file(&パス);
    let Ok(目録) = 読込結果 else {
        panic!("実行時チャンク目録をファイルから読めなかった");
    };
    assert_eq!(目録.件数(), 2);
    assert!(目録.存在するか(チャンク座標::生成する(0, 0)));
}

fn 試験用目録() -> チャンク目録 {
    let mut 目録 = チャンク目録::空を作る();
    登録する(&mut 目録, チャンク座標::生成する(-2, 1), "chunk_x-2_z1");
    登録する(&mut 目録, チャンク座標::生成する(0, 0), "chunk_x0_z0");
    目録
}

fn 登録する(目録: &mut チャンク目録, チャンク: チャンク座標, 名前: &str) {
    let Ok(アセット) = アセットID::生成する(名前) else {
        panic!("試験用IDを生成できなかった");
    };
    if let Err(誤り) = 目録.登録する(チャンク, アセット) {
        panic!("試験用目録へ登録できなかった: {誤り}");
    }
}
