//! 制定した目盛と線形の境界値の検査。どの輝度がどのビンへ入るかを、境界ちょうどの値まで含めて見る。

#![allow(clippy::unwrap_used)]

use super::histogram_scale::{ビンが覆う対数輝度の幅, 範囲の上端の対数輝度, 範囲の下端の対数輝度};
use super::{
    ビンの添字, ビンの添字を求める, ビン数, 全ビンの添字, 境界の線形輝度, 最後のビンの添字, 正の相対輝度
};

/// 単精度の刻み1つぶんの許容。境界の値が2の冪と一致することを、丸めの1単位まで許して見る。
fn 一単位以内(左: f32, 右: f32) -> bool {
    (左 - 右).abs() <= f32::EPSILON * 右.abs()
}

fn 正の輝度(値: f32) -> 正の相対輝度 {
    正の相対輝度::生成する(値).unwrap()
}

#[test]
fn ビンの本数と幅が制定した範囲を過不足なく覆う() {
    assert_eq!(usize::from(最後のビンの添字) + 1, ビン数);
    assert_eq!(全ビンの添字().count(), ビン数);
    let 最後の区間の上端 = ビンの添字::生成する(最後のビンの添字).unwrap().区間の下端の対数輝度().値() + ビンが覆う対数輝度の幅;
    assert_eq!(最後の区間の上端, 範囲の上端の対数輝度);
    assert_eq!(ビンの添字::生成する(0).unwrap().区間の下端の対数輝度().値(), 範囲の下端の対数輝度);
    const { assert!(ビンが覆う対数輝度の幅 <= 0.25) };
}

#[test]
fn 線形の境界値は区間の下端の対数輝度と対応する() {
    let mut 前 = 0.0;
    for 添字 in 全ビンの添字() {
        let 境界 = 境界の線形輝度[添字.配列の位置()];
        assert!(境界 > 前, "境界が昇順でない: {添字:?}");
        assert!(
            一単位以内(境界, 添字.区間の下端の対数輝度().値().exp2()),
            "境界が2の冪と食い違う: {添字:?}"
        );
        前 = 境界;
    }
}

#[test]
fn 整数の段に当たる境界は2の整数乗そのものである() {
    for (添字, 期待) in [(0usize, 6.103_515_6e-5), (32, 1.953_125e-3), (64, 6.25e-2), (96, 2.0)] {
        assert_eq!(境界の線形輝度[添字], 期待, "整数の段の境界が正確でない: {添字}");
    }
}

#[test]
fn 境界ちょうどの輝度は明るい側のビンへ入る() {
    for 添字 in 全ビンの添字().skip(1) {
        let 境界 = 境界の線形輝度[添字.配列の位置()];
        assert_eq!(ビンの添字を求める(正の輝度(境界)), 添字, "境界ちょうどがそのビンへ入らない");
        assert_eq!(
            ビンの添字を求める(正の輝度(境界.next_down())).値(),
            添字.値() - 1,
            "境界の直前が1つ下のビンへ入らない"
        );
    }
}

#[test]
fn 範囲の外の輝度は捨てずに端のビンへ張り付く() {
    assert_eq!(ビンの添字を求める(正の輝度(f32::MIN_POSITIVE)).値(), 0);
    assert_eq!(ビンの添字を求める(正の輝度(1.0e30)).値(), 最後のビンの添字);
}

#[test]
fn ビンの添字は範囲の外を拒む() {
    assert!(ビンの添字::生成する(最後のビンの添字).is_ok());
    assert!(ビンの添字::生成する(最後のビンの添字 + 1).is_err());
}

#[test]
fn 代表する対数輝度は区間の中央である() {
    let 添字 = ビンの添字::生成する(64).unwrap();
    assert_eq!(
        添字.代表する対数輝度().値(),
        添字.区間の下端の対数輝度().値() + ビンが覆う対数輝度の幅 * 0.5
    );
}
