//! 目標補正段の導出が返す報告。目標そのものと、その値をどう作ったかを読むための内訳を持つ。
//!
//! 両端の到達率を別々に持つのは、明部の飽和と暗部の潰れのどちらが起きているかを合算で消さないためである。
//! 制定した範囲の再制定が要るかどうかは、この2つを別々に見て判定する
//! (`参照: _doc/設計/放射輝度問い合わせ階層.md`「実測とヒストグラム範囲の制定(2026-08-04)」)。

use super::{画素の割合, 画素件数};
use crate::sky::露出補正段;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 露出の導出結果 {
    目標補正段: 露出補正段,
    切り詰めた対数輝度の平均: f32,
    上端のビンの到達率: 画素の割合,
    下端のビンの到達率: 画素の割合,
    零以下の件数: 画素件数,
}

impl 露出の導出結果 {
    pub(super) fn 生成する(
        目標補正段: 露出補正段,
        切り詰めた対数輝度の平均: f32,
        上端のビンの到達率: 画素の割合,
        下端のビンの到達率: 画素の割合,
        零以下の件数: 画素件数,
    ) -> Self {
        Self {
            目標補正段,
            切り詰めた対数輝度の平均,
            上端のビンの到達率,
            下端のビンの到達率,
            零以下の件数,
        }
    }

    /// 上下限へ収めた後の目標。時間適応の目標として使う。
    pub fn 目標補正段(&self) -> 露出補正段 {
        self.目標補正段
    }

    /// 上下1パーセントを除いた窓の中の対数輝度の平均。上下限で切られる前の画の明るさを表す。
    pub fn 切り詰めた対数輝度の平均(&self) -> f32 {
        self.切り詰めた対数輝度の平均
    }

    pub fn 上端のビンの到達率(&self) -> 画素の割合 {
        self.上端のビンの到達率
    }

    pub fn 下端のビンの到達率(&self) -> 画素の割合 {
        self.下端のビンの到達率
    }

    /// 対数平均の対象から外した、0以下の輝度の画素の件数。
    pub fn 零以下の件数(&self) -> 画素件数 {
        self.零以下の件数
    }
}
