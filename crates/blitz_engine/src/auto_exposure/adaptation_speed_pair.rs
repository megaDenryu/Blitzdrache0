//! 補正段を下げるときと上げるときで別々に持つ、露出の追従の速さの組。
//!
//! 2つを別の値として持つのは、方向を取り違えた実装をテストで反証できる形にするためであり、
//! 片方だけを速くする調整が必ず起きるためである。画が明るくなったときは補正段を下げ、暗くなったときは上げる。
//!
//! 既定値は、人間の明順応が暗順応より速いことに合わせた仮置きである。明るい場所へ出たときに眩しさが引くまでの
//! 時間は、暗い場所へ入ってから見えるようになるまでの時間より短い。最終値はGPUへ繋いだ後のオーナーの絵の目視で裁定する。

use super::補正段毎秒;

const 補正段を下げる既定の速さ: f32 = 3.0;
const 補正段を上げる既定の速さ: f32 = 1.0;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 露出の適応速度 {
    補正段を下げる速さ: 補正段毎秒,
    補正段を上げる速さ: 補正段毎秒,
}

impl 露出の適応速度 {
    pub fn 生成する(補正段を下げる速さ: 補正段毎秒, 補正段を上げる速さ: 補正段毎秒) -> Self {
        Self {
            補正段を下げる速さ,
            補正段を上げる速さ,
        }
    }

    /// 定数から作るため、ここでの失敗は定数が不正であることを意味する(プログラムのバグ)。
    pub fn 既定値() -> Self {
        Self::生成する(速さを作る(補正段を下げる既定の速さ), 速さを作る(補正段を上げる既定の速さ))
    }

    pub fn 補正段を下げる速さ(&self) -> 補正段毎秒 {
        self.補正段を下げる速さ
    }

    pub fn 補正段を上げる速さ(&self) -> 補正段毎秒 {
        self.補正段を上げる速さ
    }
}

fn 速さを作る(値: f32) -> 補正段毎秒 {
    補正段毎秒::生成する(値).unwrap_or_else(|誤り| panic!("露出の適応速度の既定値が不正だった: {誤り}"))
}
