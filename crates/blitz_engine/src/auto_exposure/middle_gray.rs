//! 目標中間灰: 切り詰めた対数平均をここへ写すという、自動露出の狙いを表す線形輝度。

use super::自動露出エラー;

/// 既定の線形輝度。写真で基準の反射面に使う18パーセントグレー(反射率18パーセントの面)の値であり、
/// 中庸な明るさの被写体の平均がここへ来ることを狙う値として広く使われている。
/// 最終的な値はGPUへ繋いだ後のオーナーの絵の目視で裁定する。
const 既定の線形輝度: f32 = 0.18;

/// 不変条件: 有限かつ0より大きい。log2を採るため0以下は定義できない。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 目標中間灰(f32);

impl 目標中間灰 {
    pub fn 生成する(線形輝度: f32) -> Result<Self, 自動露出エラー> {
        if !線形輝度.is_finite() || 線形輝度 <= 0.0 {
            return Err(自動露出エラー::値域外("目標中間灰", 線形輝度));
        }
        Ok(Self(線形輝度))
    }

    pub fn 既定値() -> Self {
        Self(既定の線形輝度)
    }

    pub fn 線形輝度(&self) -> f32 {
        self.0
    }

    /// 対数平均と同じ目盛で比べるための対数輝度。線形0.18は約-2.474EVである。
    pub fn 対数輝度で表す(&self) -> f32 {
        self.0.log2()
    }
}
