//! 目標中間灰: 切り詰めた対数輝度の平均をここへ写すという、自動露出の狙いを表す明るさ。

use super::{対数輝度, 正の相対輝度, 自動露出エラー};

/// 既定の線形輝度。写真で基準の反射面に使う18パーセントグレー(反射率18パーセントの面)の値であり、
/// 中庸な明るさの被写体の平均がここへ来ることを狙う値として広く使われている。
/// 最終的な値はGPUへ繋いだ後のオーナーの絵の目視で裁定する。
const 既定の線形輝度: f32 = 0.18;

#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 目標中間灰(正の相対輝度);

impl 目標中間灰 {
    pub fn 生成する(線形輝度: f32) -> Result<Self, 自動露出エラー> {
        Ok(Self(正の相対輝度::生成する(線形輝度)?))
    }

    /// 定数から作るため、ここでの失敗は定数が不正であることを意味する(プログラムのバグ)。
    pub fn 既定値() -> Self {
        Self::生成する(既定の線形輝度).unwrap_or_else(|誤り| panic!("目標中間灰の既定値が不正だった: {誤り}"))
    }

    pub fn 相対輝度(&self) -> 正の相対輝度 {
        self.0
    }

    /// 平均と同じ目盛で比べるための対数輝度。線形0.18は約-2.474EVである。
    pub fn 対数輝度で表す(&self) -> 対数輝度 {
        self.0.対数輝度で表す()
    }
}
