//! 輝度の区分と集計の検査。画素が3つの枠のどれへ入るかと、2つの入口が同じ結果を作ることを見る。

#![allow(clippy::unwrap_used)]

use super::histogram_boundary::境界の線形輝度;
use super::luminance::{相対輝度を求める, 緑の重み, 赤の重み, 青の重み};
use super::{
    ビンの添字, ビンの添字を求める, 正の相対輝度, 画素を区分する, 画素件数, 画素列から集計する, 輝度の区分, 輝度列から集計する
};

/// 2の1乗に当たる境界を持つビンの添字。境界がちょうど2.0であり、またぐ画素を人が読める値で書ける。
const 二の一乗の境界のビン: u8 = 96;

/// 相対輝度が2.0の境界のすぐ上に落ちる画素。積の丸めを省く積和融合で計算すると境界の下側へ落ち、
/// 1つ下のビンへ入る。将来のCPUとGPUの一致検査はこの組を含めて、写しが積和融合を使っていないことを反証する。
const 積和融合で答えが変わる画素: [f32; 3] = [0.54217917, 1.7448004, 8.820656];

#[test]
fn 相対輝度は成分ごとに定めた重みを掛ける() {
    assert_eq!(相対輝度を求める(1.0, 0.0, 0.0), 赤の重み);
    assert_eq!(相対輝度を求める(0.0, 1.0, 0.0), 緑の重み);
    assert_eq!(相対輝度を求める(0.0, 0.0, 1.0), 青の重み);
}

#[test]
fn 境界をまたぐ画素の対は別のビンへ入る() {
    let 境界 = 境界の線形輝度[usize::from(二の一乗の境界のビン)];
    let 直下 = 境界.next_down();
    assert_eq!(相対輝度を求める(境界, 境界, 境界), 境界, "灰色の画素の相対輝度が境界ちょうどにならない");
    assert_eq!(
        画素を区分する(境界, 境界, 境界),
        輝度の区分::ビンへ入る(ビンの添字::生成する(二の一乗の境界のビン).unwrap())
    );
    assert!(相対輝度を求める(直下, 直下, 直下) < 境界);
    assert_eq!(
        画素を区分する(直下, 直下, 直下),
        輝度の区分::ビンへ入る(ビンの添字::生成する(二の一乗の境界のビン - 1).unwrap())
    );
}

#[test]
fn 積の丸めを省くと答えが変わる画素は境界の上側のビンへ入る() {
    let [赤, 緑, 青] = 積和融合で答えが変わる画素;
    assert_eq!(
        相対輝度を求める(赤, 緑, 青),
        境界の線形輝度[usize::from(二の一乗の境界のビン)],
        "固定した画素が境界ちょうどに落ちない"
    );
    assert_eq!(
        画素を区分する(赤, 緑, 青),
        輝度の区分::ビンへ入る(ビンの添字::生成する(二の一乗の境界のビン).unwrap())
    );
}

#[test]
fn 零以下と非有限は別枠へ数える() {
    assert_eq!(画素を区分する(0.0, 0.0, 0.0), 輝度の区分::零以下);
    assert_eq!(画素を区分する(-1.0, 0.0, 0.0), 輝度の区分::零以下);
    assert_eq!(画素を区分する(f32::NAN, 0.0, 0.0), 輝度の区分::非有限);
    assert_eq!(画素を区分する(f32::INFINITY, 0.0, 0.0), 輝度の区分::非有限);
}

#[test]
fn 集計は3つの枠へ画素を振り分ける() {
    let ヒストグラム = 輝度列から集計する([1.0, 1.0, 0.0, -2.0, f32::NAN, 1.0e30, 1.0e-30]);
    let 輝度1のビン = ビンの添字を求める(正の相対輝度::生成する(1.0).unwrap());
    assert_eq!(ヒストグラム.ビンの件数(輝度1のビン), 画素件数::生成する(2));
    assert_eq!(ヒストグラム.零以下の件数(), 画素件数::生成する(2));
    assert_eq!(ヒストグラム.非有限の件数(), 画素件数::生成する(1));
    assert_eq!(ヒストグラム.上端のビンの件数(), 画素件数::生成する(1));
    assert_eq!(ヒストグラム.下端のビンの件数(), 画素件数::生成する(1));
    assert_eq!(ヒストグラム.ビンへ入った総数(), 画素件数::生成する(4));
}

#[test]
fn 画素の列と相対輝度の列は同じヒストグラムを作る() {
    let 画素列 = [[1.0, 1.0, 1.0], [0.0, 0.5, 0.0], [-1.0, 0.0, 0.0], [f32::NAN, 0.0, 0.0]];
    let 輝度列 = 画素列.map(|[赤, 緑, 青]| 相対輝度を求める(赤, 緑, 青));
    assert_eq!(画素列から集計する(画素列), 輝度列から集計する(輝度列));
}
