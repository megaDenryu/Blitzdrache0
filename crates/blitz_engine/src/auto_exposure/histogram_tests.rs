//! 輝度の区分と集計の検査。画素が3つの枠のどれへ入るかと、2つの入口が同じ結果を作ることを見る。

#![allow(clippy::unwrap_used)]

use super::{
    ビンの添字を求める, 正の相対輝度, 画素を区分する, 画素件数, 画素列から集計する, 相対輝度を求める, 緑の重み, 赤の重み, 輝度の区分,
    輝度列から集計する, 青の重み,
};

#[test]
fn 相対輝度は成分ごとに定めた重みを掛ける() {
    assert_eq!(相対輝度を求める(1.0, 0.0, 0.0), 赤の重み);
    assert_eq!(相対輝度を求める(0.0, 1.0, 0.0), 緑の重み);
    assert_eq!(相対輝度を求める(0.0, 0.0, 1.0), 青の重み);
}

#[test]
fn 零以下と非有限は別枠へ数える() {
    assert_eq!(画素を区分する(0.0, 0.0, 0.0), 輝度の区分::零以下);
    assert_eq!(画素を区分する(-1.0, 0.0, 0.0), 輝度の区分::零以下);
    assert_eq!(画素を区分する(f32::NAN, 0.0, 0.0), 輝度の区分::非有限);
    assert_eq!(画素を区分する(f32::INFINITY, 0.0, 0.0), 輝度の区分::非有限);
}

#[test]
fn 集計は3つの枠へ画素を振り分ける() {
    let ヒストグラム = 輝度列から集計する([1.0, 1.0, 0.0, -2.0, f32::NAN, 1.0e30, 1.0e-30]);
    let 輝度1のビン = ビンの添字を求める(正の相対輝度::生成する(1.0).unwrap());
    assert_eq!(ヒストグラム.ビンの件数(輝度1のビン), 画素件数::生成する(2));
    assert_eq!(ヒストグラム.零以下の件数(), 画素件数::生成する(2));
    assert_eq!(ヒストグラム.非有限の件数(), 画素件数::生成する(1));
    assert_eq!(ヒストグラム.上端のビンの件数(), 画素件数::生成する(1));
    assert_eq!(ヒストグラム.下端のビンの件数(), 画素件数::生成する(1));
    assert_eq!(ヒストグラム.ビンへ入った総数(), 画素件数::生成する(4));
}

#[test]
fn 画素の列と相対輝度の列は同じヒストグラムを作る() {
    let 画素列 = [[1.0, 1.0, 1.0], [0.0, 0.5, 0.0], [-1.0, 0.0, 0.0], [f32::NAN, 0.0, 0.0]];
    let 輝度列 = 画素列.map(|[赤, 緑, 青]| 相対輝度を求める(赤, 緑, 青));
    assert_eq!(画素列から集計する(画素列), 輝度列から集計する(輝度列));
}
