//! 制定した目盛と集計の検査。ビンの割り当てと、log2が定まらない画素を別枠へ分けることを見る。

#![allow(clippy::unwrap_used)]

use super::{
    ビンが覆う対数輝度の幅, ビンの添字, ビンの添字を求める, ビン数, 全ビンの添字, 最後のビンの添字, 画素を区分する, 画素件数, 画素列から集計する,
    相対輝度を求める, 範囲の上端の対数輝度, 範囲の下端の対数輝度, 緑の重み, 赤の重み, 輝度の区分, 輝度列から集計する, 青の重み,
};

#[test]
fn ビンの本数と幅が制定した範囲を過不足なく覆う() {
    assert_eq!(usize::from(最後のビンの添字) + 1, ビン数);
    assert_eq!(全ビンの添字().count(), ビン数);
    let 最後の区間の上端 = ビンの添字::生成する(最後のビンの添字).unwrap().区間の下端の対数輝度() + ビンが覆う対数輝度の幅;
    assert_eq!(最後の区間の上端, 範囲の上端の対数輝度);
    assert_eq!(ビンの添字::生成する(0).unwrap().区間の下端の対数輝度(), 範囲の下端の対数輝度);
    const { assert!(ビンが覆う対数輝度の幅 <= 0.25) };
}

#[test]
fn ビンの添字は範囲の外を拒む() {
    assert!(ビンの添字::生成する(最後のビンの添字).is_ok());
    assert!(ビンの添字::生成する(最後のビンの添字 + 1).is_err());
}

#[test]
fn 代表する対数輝度は区間の中央である() {
    let 添字 = ビンの添字::生成する(64).unwrap();
    assert_eq!(添字.代表する対数輝度(), 添字.区間の下端の対数輝度() + ビンが覆う対数輝度の幅 * 0.5);
}

#[test]
fn 範囲の外の輝度は捨てずに端のビンへ張り付く() {
    assert_eq!(ビンの添字を求める(範囲の下端の対数輝度 - 100.0).値(), 0);
    assert_eq!(ビンの添字を求める(範囲の上端の対数輝度 + 100.0).値(), 最後のビンの添字);
    assert_eq!(ビンの添字を求める(範囲の下端の対数輝度).値(), 0);
}

#[test]
fn 区間の下端はそのビンへ入り直前の値は1つ下のビンへ入る() {
    for 添字 in 全ビンの添字().skip(1) {
        assert_eq!(ビンの添字を求める(添字.区間の下端の対数輝度()), 添字, "下端がそのビンへ入らない");
        assert_eq!(
            ビンの添字を求める(添字.区間の下端の対数輝度() - ビンが覆う対数輝度の幅 * 0.5).値(),
            添字.値() - 1
        );
    }
}

#[test]
fn 相対輝度は成分ごとに定めた重みを掛ける() {
    assert_eq!(相対輝度を求める(1.0, 0.0, 0.0), 赤の重み);
    assert_eq!(相対輝度を求める(0.0, 1.0, 0.0), 緑の重み);
    assert_eq!(相対輝度を求める(0.0, 0.0, 1.0), 青の重み);
}

#[test]
fn 零以下と非有限は別枠へ数える() {
    assert_eq!(画素を区分する(0.0, 0.0, 0.0), 輝度の区分::零以下);
    assert_eq!(画素を区分する(-1.0, 0.0, 0.0), 輝度の区分::零以下);
    assert_eq!(画素を区分する(f32::NAN, 0.0, 0.0), 輝度の区分::非有限);
    assert_eq!(画素を区分する(f32::INFINITY, 0.0, 0.0), 輝度の区分::非有限);
}

#[test]
fn 集計は3つの枠へ画素を振り分ける() {
    let ヒストグラム = 輝度列から集計する([1.0, 1.0, 0.0, -2.0, f32::NAN, 1.0e30, 1.0e-30]);
    let 輝度1のビン = ビンの添字を求める(0.0);
    assert_eq!(ヒストグラム.ビンの件数(輝度1のビン), 画素件数::生成する(2));
    assert_eq!(ヒストグラム.零以下の件数(), 画素件数::生成する(2));
    assert_eq!(ヒストグラム.非有限の件数(), 画素件数::生成する(1));
    assert_eq!(ヒストグラム.上端のビンの件数(), 画素件数::生成する(1));
    assert_eq!(ヒストグラム.下端のビンの件数(), 画素件数::生成する(1));
    assert_eq!(ヒストグラム.ビンへ入った総数(), 画素件数::生成する(4));
}

#[test]
fn 画素の列と相対輝度の列は同じヒストグラムを作る() {
    let 画素列 = [[1.0, 1.0, 1.0], [0.0, 0.5, 0.0], [-1.0, 0.0, 0.0], [f32::NAN, 0.0, 0.0]];
    let 輝度列 = 画素列.map(|[赤, 緑, 青]| 相対輝度を求める(赤, 緑, 青));
    assert_eq!(画素列から集計する(画素列), 輝度列から集計する(輝度列));
}
