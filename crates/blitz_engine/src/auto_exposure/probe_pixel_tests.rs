//! GPUの写しが積和融合を使っていないことを実機で反証するための探り色の検査。
//!
//! この画素は3成分とも半精度で正確に表せる。半精度のHDR中間画像を通しても値が変わらないため、検収は
//! この色で背景を埋めた絵を描き、CPU正本とGPUが同じビンへ入れたかを見られる
//! (`xtask/src/auto_exposure/run.rs`が同じ値と同じ添字を持つ)。
//!
//! 積の丸めを省く計算では相対輝度が単精度で1つ下の値になり、1つ下のビンへ入る。境界ちょうどに落ちる組と
//! 半精度で表せる制約の両方を満たす組は探索で見つけた。

#![allow(clippy::unwrap_used)]

use super::histogram_boundary::境界の線形輝度;
use super::luminance::相対輝度を求める;
use super::{ビンの添字, 画素を区分する, 輝度の区分};

/// 探り色の線形RGB。`xtask/src/auto_exposure/run.rs`の`探り色`と同じ値である。
const 探り色: [f32; 3] = [0.062561035, 0.19641113, 0.42700195];
/// 探り色が入るビンの添字。`xtask/src/auto_exposure/run.rs`の`探り色のビンの添字`と同じ値である。
const 探り色のビンの添字: u8 = 74;

/// 単精度の値を半精度へ丸めて戻す。ビット演算だけで行い、丸めは最近接偶数へ寄せる。
fn 半精度を往復する(値: f32) -> f32 {
    let ビット = 値.to_bits();
    let 指数 = i32::try_from((ビット >> 23) & 0xff).unwrap() - 127 + 15;
    let 仮数 = ビット & 0x7f_ffff;
    assert!((1..31).contains(&指数), "探り色の成分が半精度の正規化数の範囲に無い: {値}");
    let 丸めた仮数 = (仮数 + 0x1000) >> 13;
    assert!(丸めた仮数 <= 0x3ff, "探り色の成分の丸めが指数を繰り上げる: {値}");
    f32::from_bits((ビット & 0x8000_0000) | (u32::try_from(指数 + 112).unwrap() << 23) | (丸めた仮数 << 13))
}

#[test]
fn 探り色は半精度で正確に表せる() {
    for 成分 in 探り色 {
        assert_eq!(半精度を往復する(成分), 成分, "探り色の成分が半精度で丸められる: {成分}");
    }
}

#[test]
fn 探り色は境界ちょうどに落ちて上側のビンへ入る() {
    let [赤, 緑, 青] = 探り色;
    assert_eq!(
        相対輝度を求める(赤, 緑, 青),
        境界の線形輝度[usize::from(探り色のビンの添字)],
        "探り色が境界ちょうどに落ちない"
    );
    assert_eq!(
        画素を区分する(赤, 緑, 青),
        輝度の区分::ビンへ入る(ビンの添字::生成する(探り色のビンの添字).unwrap())
    );
}

#[test]
fn 積の丸めを省くと探り色は1つ下のビンへ入る() {
    let [赤, 緑, 青] = 探り色;
    let 融合した輝度 = 青.mul_add(0.0722, 緑.mul_add(0.7152, 赤 * 0.2126));
    assert!(
        融合した輝度 < 境界の線形輝度[usize::from(探り色のビンの添字)],
        "積和融合で答えが変わらない探り色になっている"
    );
    assert!(融合した輝度 >= 境界の線形輝度[usize::from(探り色のビンの添字 - 1)]);
}
