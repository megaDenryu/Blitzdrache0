//! 自動補正段の上下限: 自動露出が動いてよいEVの帯。導いた目標補正段をこの帯へ収める。

use super::自動露出エラー;
use crate::sky::露出補正段;

/// 既定の下限。現行の時刻別固定補正(昼0EV・夜+2EV)を帯へ含むことが制定の最低条件であり、
/// 明るすぎる画を暗くする余地として-4EVを採る。
const 既定の下限の段: f32 = -4.0;
/// 既定の上限。夜のp50が-11.22EVであり、この上限まで持ち上げても-5.2EV前後にとどまるため夜の暗さが残る。
/// 夜をどこまで持ち上げるかは絵の判断であり、この値は仮置きである。最終値はGPUへ繋いだ後のオーナーの絵の目視で裁定する。
const 既定の上限の段: f32 = 6.0;

/// 不変条件: 下限と上限がともに有限であり、下限が上限以下である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 自動補正段の上下限 {
    下限: 露出補正段,
    上限: 露出補正段,
}

impl 自動補正段の上下限 {
    pub fn 生成する(下限: 露出補正段, 上限: 露出補正段) -> Result<Self, 自動露出エラー> {
        if 下限.値() > 上限.値() {
            return Err(自動露出エラー::上下限の順序が逆 {
                下限: 下限.値(),
                上限: 上限.値(),
            });
        }
        Ok(Self { 下限, 上限 })
    }

    /// 段の生値から作る入口。非有限は露出補正段の検証が拒み、そのエラーを型付きのまま運ぶ。
    pub fn 段の値から生成する(下限の値: f32, 上限の値: f32) -> Result<Self, 自動露出エラー> {
        Self::生成する(露出補正段::生成する(下限の値)?, 露出補正段::生成する(上限の値)?)
    }

    /// 定数から作るため、ここでの失敗は定数が不正であることを意味する(プログラムのバグ)。
    pub fn 既定値() -> Self {
        Self::段の値から生成する(既定の下限の段, 既定の上限の段).unwrap_or_else(|誤り| panic!("自動補正段の上下限の既定値が不正だった: {誤り}"))
    }

    pub fn 下限(&self) -> 露出補正段 {
        self.下限
    }

    pub fn 上限(&self) -> 露出補正段 {
        self.上限
    }

    /// 段を帯へ収める。上下限も入力も有限であるため、収めた結果も有限であり露出補正段の検証は通る。
    pub fn 収める(&self, 段: 露出補正段) -> 露出補正段 {
        let 収めた = 段.値().clamp(self.下限.値(), self.上限.値());
        露出補正段::生成する(収めた).unwrap_or_else(|誤り| panic!("有限の段を有限の帯へ収めた結果が値域を外れた: {誤り}"))
    }
}
