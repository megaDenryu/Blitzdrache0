//! 明るさの圧縮を通す前のHDRの1画素と、その画素の相対輝度。どちらもGPUから読み戻した値そのものを表す。
//!
//! 値域の検証を持たないのは、この層の入口が受け取るのが読み戻した生の観測であり、負や非有限を含みうるためである。
//! ここで弾くと、ヒストグラムを作る前に画素を捨てる判断をすることになる。3つの枠(ビン・零以下・非有限)の
//! どれへ入るかを決めるのは`輝度の区分`であり、そこまで値を落とさずに運ぶ。
//!
//! それでも生の単精度で受け取らないのは、この層に明るさの目盛が3つあるためである。線形の輝度・対数輝度・
//! 補正段はどれも単精度1つで表され、取り違えても署名が通る。型を分けることで、対数の目盛の値を
//! 線形の境界と比べる呼び出しを書けなくする。

/// 明るさの圧縮を通す前のHDRの1画素。成分の並びは赤・緑・青である。
#[repr(transparent)]
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 明るさの圧縮前のHDR画素([f32; 3]);

impl 明るさの圧縮前のHDR画素 {
    pub fn 生成する(赤: f32, 緑: f32, 青: f32) -> Self {
        Self([赤, 緑, 青])
    }

    /// 読み戻した成分の並びから作る。並びは赤・緑・青である。
    pub fn 成分から生成する(成分: [f32; 3]) -> Self {
        Self(成分)
    }

    pub(super) fn 成分(self) -> [f32; 3] {
        self.0
    }
}

/// 明るさの圧縮を通す前のHDRの相対輝度。線形の目盛の値であり、負も非有限も取りうる。
#[repr(transparent)]
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 明るさの圧縮前の相対輝度(f32);

impl 明るさの圧縮前の相対輝度 {
    pub fn 生成する(値: f32) -> Self {
        Self(値)
    }

    /// 線形の境界値との比較と、正の相対輝度への絞り込みだけがこの入口を使う。
    pub fn 値(self) -> f32 {
        self.0
    }
}
