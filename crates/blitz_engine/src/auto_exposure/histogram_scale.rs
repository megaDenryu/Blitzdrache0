//! 制定した対数輝度の目盛。どの値がどのビンへ入るかと、ビンがどの対数輝度を代表するかを1箇所で決める。
//!
//! 対数輝度とは相対輝度を2の対数で表した値のことであり、単位はEV(2を底とする段数)である。輝度1.0が0EVになる。
//!
//! 範囲と刻みの根拠は実測にある(`参照: _doc/設計/放射輝度問い合わせ階層.md`「実測とヒストグラム範囲の制定(2026-08-04)」)。
//! 目視見本の庭の4時刻でp1の最小が-11.50EV、p99の最大が0.57EVであり、両側2EVの余白を覆う範囲として制定した。
//! 上端を+6EVまで広げるのは、正午の画面最大5.66EVを範囲へ収めて上端の張り付きを通常の4時刻で起こさないためである。
//!
//! 注意: この範囲は目視見本の庭という単一の構図で採った校正値であり、あらゆるシーンが収まる証明ではない。
//! 範囲の外の画素は捨てずに端のビンへ入れ、両端の到達率を別々に報告することで再制定の必要を観測できるようにする。

use super::自動露出エラー;

/// ヒストグラムが覆う範囲の下端。
pub const 範囲の下端の対数輝度: f32 = -14.0;
/// ヒストグラムが覆う範囲の上端。
pub const 範囲の上端の対数輝度: f32 = 6.0;
/// ビンの本数。
pub const ビン数: usize = 128;
/// 1つのビンが覆う幅。範囲の幅20EVをビンの本数で割った値であり、制定条件の0.25EV以下を満たす。
pub const ビンが覆う対数輝度の幅: f32 = 0.15625;
/// 最後のビンの添字。ビンの本数との整合は単体テストが見る。
pub const 最後のビンの添字: u8 = 127;

/// ヒストグラムのビンを指す添字。不変条件: ビンの本数未満である。
///
/// 添字を8ビットで持つのは、128本という制定値が8ビットに収まり、標準ライブラリが8ビット整数から
/// 単精度への型付き変換を持つためである。ビンが代表する対数輝度を求めるのに`as`キャストが要らなくなる。
/// ビンの本数を256より増やす制定改訂は、この型の幅の変更を伴う。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct ビンの添字(u8);

impl ビンの添字 {
    pub fn 生成する(値: u8) -> Result<Self, 自動露出エラー> {
        if 値 > 最後のビンの添字 {
            return Err(自動露出エラー::ビンの添字が範囲外(値));
        }
        Ok(Self(値))
    }

    pub fn 値(&self) -> u8 {
        self.0
    }

    /// ビンごとの配列を参照するときの位置。
    pub fn 配列の位置(&self) -> usize {
        usize::from(self.0)
    }

    /// このビンが覆う区間の下端。
    pub fn 区間の下端の対数輝度(&self) -> f32 {
        範囲の下端の対数輝度 + f32::from(self.0) * ビンが覆う対数輝度の幅
    }

    /// このビンを代表する値。区間の中央を採る。
    pub fn 代表する対数輝度(&self) -> f32 {
        self.区間の下端の対数輝度() + ビンが覆う対数輝度の幅 * 0.5
    }
}

/// すべてのビンの添字を昇順に並べる。値域はこの列挙が満たすため、検証付きの生成を通らない。
pub fn 全ビンの添字() -> impl Iterator<Item = ビンの添字> {
    (0..=最後のビンの添字).map(ビンの添字)
}

/// 対数輝度が入るビンを求める。範囲の外は捨てずに端のビンへ張り付ける。
///
/// 比較だけで求めるのは、浮動小数から整数への安全な標準変換が無い(`as`キャストは規約で禁止)ことに加え、
/// 乗算の丸めに依存しない定義にするとGPUの写しが同じ添字を再現できるためである。区間の下端は-14に
/// 0.15625の整数倍を足した値であり、いずれも単精度で正確に表せる。
/// 前提: 非有限の輝度はここへ渡さない(区分の段が別枠へ分ける)。
pub fn ビンの添字を求める(対数輝度: f32) -> ビンの添字 {
    let mut 下 = 0u8;
    let mut 上 = 最後のビンの添字;
    while 下 < 上 {
        let 中 = 下 + (上 - 下).div_ceil(2);
        if ビンの添字(中).区間の下端の対数輝度() <= 対数輝度 {
            下 = 中;
        } else {
            上 = 中 - 1;
        }
    }
    ビンの添字(下)
}
