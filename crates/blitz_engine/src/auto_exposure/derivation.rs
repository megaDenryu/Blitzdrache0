//! ヒストグラムから目標の露出補正段を導く工程。受け取るのはヒストグラムと狙いの設定、返すのは導出結果である。
//!
//! 上下1パーセントを除くのは、太陽円盤のような少数の極端に明るい画素や、画面の隅の潰れた暗部が平均を
//! 支配しないためである。除外する件数は整数の除算で決め、ビンを添字の昇順に走って窓に重なる件数だけを重みにする。
//! 切り詰めた平均は、窓に重なる件数を重みにした添字の整数の総和(`添字の重み付き総和`)から作る。これが正本の定義であり、
//! GPUの写しも同じ整数を作る。整数の加算は足す順にも結合の順にも依存しないため、この中間値は必ずバイト一致する。
//! 走査を単一の呼び出しに保つのは順序のためではなく、窓との重なりを求めるのに走査済みの件数を順に積む必要があるためである。
//!
//! 母数はビンへ入った総数であり、0以下と非有限の画素は分母にも分子にも入らない。両端の到達率も同じ母数で採る。

use super::histogram_scale::添字の平均が代表する対数輝度;
use super::{
    対数輝度, 添字の重み付き総和, 画素の割合, 画素件数, 目標中間灰, 自動補正段の上下限, 自動露出エラー, 輝度ヒストグラム, 露出の導出結果
};

/// 片側で除外する件数を決める除数。上下それぞれ1パーセントを外すため、総数を100で割る。
const 片側の除外を決める除数: u32 = 100;

pub fn 目標補正段を導く(
    ヒストグラム: &輝度ヒストグラム,
    目標中間灰: 目標中間灰,
    上下限: 自動補正段の上下限,
) -> Result<露出の導出結果, 自動露出エラー> {
    let 総数 = ヒストグラム.ビンへ入った総数();
    if 総数.値() == 0 {
        return Err(自動露出エラー::ビンへ入った画素が無い);
    }
    let (統計量, 窓の件数) = 窓の中の添字の重み付き総和を求める(ヒストグラム, 総数)?;
    let 平均 = 切り詰めた対数輝度の平均を求める(統計量, 窓の件数)?;
    let 目標 = 平均.写すための補正段(目標中間灰.対数輝度で表す())?;
    Ok(露出の導出結果::生成する(
        上下限.収める(目標),
        平均,
        統計量,
        画素の割合::件数の比から求める(ヒストグラム.上端のビンの件数(), 総数)?,
        画素の割合::件数の比から求める(ヒストグラム.下端のビンの件数(), 総数)?,
        ヒストグラム.零以下の件数(),
    ))
}

/// 上下1パーセントを除いた窓の中で、窓に重なる件数を重みにした添字の総和と、その窓の件数。
///
/// 画素を並べ替えずに済むのは、ビンが昇順に並んでいる時点で輝度の順に並んでいるためである。
/// 窓の端はビンの途中に落ちうるため、そのビンからは窓に重なる件数だけを取り出す。
fn 窓の中の添字の重み付き総和を求める(
    ヒストグラム: &輝度ヒストグラム,
    総数: 画素件数,
) -> Result<(添字の重み付き総和, 画素件数), 自動露出エラー> {
    let 片側の除外件数 = 総数.値() / 片側の除外を決める除数;
    let 窓の開始 = 片側の除外件数;
    let 窓の終端 = 総数.値() - 片側の除外件数;
    let 窓の件数 = 窓の終端.saturating_sub(窓の開始);
    if 窓の件数 == 0 {
        return Err(自動露出エラー::ビンへ入った画素が無い);
    }
    let mut 走査済み = 0u32;
    let mut 統計量 = 添字の重み付き総和::零();
    for (添字, 件数) in ヒストグラム.ビンごとの件数() {
        let ビンの開始 = 走査済み;
        let ビンの終端 = 走査済み.saturating_add(件数.値());
        走査済み = ビンの終端;
        let 重なり = ビンの終端.min(窓の終端).saturating_sub(ビンの開始.max(窓の開始));
        統計量 = 統計量.足す(画素件数::生成する(重なり), 添字);
    }
    Ok((統計量, 画素件数::生成する(窓の件数)))
}

/// 添字の総和を件数で割って添字の平均を作り、その位置が代表する対数輝度へ写す。
/// 浮動小数が現れるのはこの3演算だけであり、それ以外は整数である。
fn 切り詰めた対数輝度の平均を求める(
    統計量: 添字の重み付き総和, 窓の件数: 画素件数
) -> Result<対数輝度, 自動露出エラー> {
    let 添字の平均 = 統計量.実数で表す() / 窓の件数.実数で表す();
    対数輝度::生成する(添字の平均が代表する対数輝度(添字の平均))
}
