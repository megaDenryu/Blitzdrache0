//! 前の補正段から次の補正段を1ステップ進める工程。受け取るのは前の状態・目標・経過時間・速さ、返すのは次の状態である。
//!
//! 実時間をこの関数の中で読まないのは、同じ入力列からは常に同じ系列が出ることを検収で確かめるためである。
//! 経過時間は呼び出し側が明示して渡す。
//!
//! 1ステップの移動量を「速さ×経過時間」で頭打ちにし、さらに目標までの残りの差より大きくしないのは、
//! 目標を跨いで振動しないためである。この2つの上限があるかぎり、系列は目標へ単調に近づく。

use blitz_math::秒;

use super::{自動露出エラー, 露出の適応速度, 露出適応状態};
use crate::sky::露出補正段;

pub fn 次の適応状態を求める(
    現在: 露出適応状態,
    目標補正段: 露出補正段,
    経過: 秒,
    速度: 露出の適応速度,
) -> Result<露出適応状態, 自動露出エラー> {
    let 経過秒 = 経過.値();
    if !経過秒.is_finite() || 経過秒 < 0.0 {
        return Err(自動露出エラー::値域外("経過秒", 経過秒));
    }
    let 露出適応状態::追従中(前の補正段) = 現在 else {
        return Ok(露出適応状態::追従中(目標補正段));
    };
    let 差 = 目標補正段.値() - 前の補正段.値();
    let 速さ = if 差 < 0.0 {
        速度.補正段を下げる速さ()
    } else {
        速度.補正段を上げる速さ()
    };
    let 移動の上限 = 速さ.値() * 経過秒;
    let 移動量 = 差.abs().min(移動の上限) * 差.signum();
    Ok(露出適応状態::追従中(露出補正段::生成する(前の補正段.値() + 移動量)?))
}
