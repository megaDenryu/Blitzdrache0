//! 露出方式と今の適応状態から、明るさの圧縮が基準の露出倍率へ掛ける最終の補正段を作る工程。
//!
//! この合成がCPU正本であり、`shaders/tonemap.slang`の`finalExposure`と`shaders/auto_exposure_state.slang`の
//! `automaticCompensationStep`がその写しである。GPU側は同じ規則を毎フレーム画素段で評価する。
//!
//! 未初期化のあいだ自動補正段を0にするのは、有効なヒストグラムを1度も得ていない状態で描くフレームの既定である。
//! 状態そのものを0で初期化するのではなく、描画値へ変換するこの境界だけが0を使う。時刻別固定へは戻さない
//! (自動を宣言した世界の明るさを2つの系統が触ることになるため)。

use super::{自動露出エラー, 露出方式, 露出適応状態};
use crate::sky::露出補正段;

pub fn 最終補正段を合成する(方式: 露出方式, 状態: 露出適応状態) -> Result<露出補正段, 自動露出エラー> {
    let 露出方式::ヒストグラム自動 { 芸術的バイアス } = 方式 else {
        // 時刻別固定の枝の補正段は昼夜方針が決め、基準の露出倍率へ畳み込み済みである。ここで足すものは無い。
        return Ok(露出補正段::生成する(0.0)?);
    };
    let 自動補正段 = 状態.補正段().map_or(0.0, |段| 段.値());
    Ok(露出補正段::生成する(芸術的バイアス.値() + 自動補正段)?)
}
