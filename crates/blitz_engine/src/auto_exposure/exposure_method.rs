//! 世界が宣言する露出の決め方。
//!
//! 世界の間接照明方針と別の型にするのは、照明の供給と画の完成が別の軸だからである。既定は時刻別固定であり、
//! 自動を選ぶ世界だけがヒストグラム自動の枝を持つ。
//!
//! 自動の枝では時刻別固定の補正段を足さない。最終倍率は基準露出倍率×2の(芸術的バイアス+自動補正段)乗である。
//! 時刻の補正と自動の補正を同時に効かせると、同じ明るさを2つの系統が別々に動かすためである。
//! この合成をフレームの経路へ配線するのはGPU側の作業であり、この型はまだどの世界からも選ばれていない
//! (`参照: _doc/設計/放射輝度問い合わせ階層.md`「IIb(自動露出)の設計」)。

use crate::sky::露出補正段;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 露出方式 {
    時刻別固定, // 昼夜方針が時刻から導く固定の補正段だけを使う
    ヒストグラム自動 { 芸術的バイアス: 露出補正段 }, // 画面全体の輝度ヒストグラムから導いた自動補正段を使う
}

impl 露出方式 {
    /// 自動の枝が持つ芸術的バイアス。時刻別固定の枝は自動補正を持たないため値が無い。
    pub fn 芸術的バイアス(&self) -> Option<露出補正段> {
        match self {
            Self::時刻別固定 => None,
            Self::ヒストグラム自動 { 芸術的バイアス } => Some(*芸術的バイアス),
        }
    }
}
