//! 時間適応の検査。固定の刻み幅の列で、単調に近づくこと・目標を跨がないこと・同じ入力から同じ系列が出ることを見る。

#![allow(clippy::unwrap_used)]

use blitz_math::秒;

use super::{次の適応状態を求める, 自動補正段の上下限, 自動露出エラー, 露出の適応速度, 露出適応状態};
use crate::sky::露出補正段;

const 刻み幅: f32 = 0.1;

fn 段(値: f32) -> 露出補正段 {
    露出補正段::生成する(値).unwrap()
}

fn 系列を作る(初期: 露出適応状態, 目標: 露出補正段, 歩数: usize) -> Vec<f32> {
    let 速度 = 露出の適応速度::既定値();
    let mut 状態 = 初期;
    let mut 系列 = Vec::new();
    for _ in 0..歩数 {
        状態 = 次の適応状態を求める(状態, 目標, 秒::生成する(刻み幅), 速度).unwrap();
        系列.push(状態.補正段().unwrap().値());
    }
    系列
}

#[test]
fn 未初期化からは補間せず目標をそのまま初期値にする() {
    let 状態 = 次の適応状態を求める(露出適応状態::未初期化, 段(3.0), 秒::生成する(刻み幅), 露出の適応速度::既定値()).unwrap();
    assert_eq!(状態, 露出適応状態::追従中(段(3.0)));
}

#[test]
fn 明るい側へは補正段を上げる速さで近づき目標を跨がない() {
    let 目標 = 段(2.0);
    let 系列 = 系列を作る(露出適応状態::追従中(段(0.0)), 目標, 40);
    let 上限の移動量 = 露出の適応速度::既定値().補正段を上げる速さ().値() * 刻み幅;
    let mut 前 = 0.0;
    for 値 in &系列 {
        assert!(*値 >= 前, "単調に増えていない");
        assert!(*値 <= 目標.値() + 1.0e-6, "目標を跨いだ: {値}");
        assert!(値 - 前 <= 上限の移動量 + 1.0e-6, "1歩の移動が速さ×刻み幅を超えた: {}", 値 - 前);
        前 = *値;
    }
    assert!((前 - 目標.値()).abs() < 1.0e-5, "20秒ぶんの歩数で目標へ到達していない: {前}");
}

#[test]
fn 暗い側へは補正段を下げる速さで近づき目標を跨がない() {
    let 目標 = 段(-2.0);
    let 系列 = 系列を作る(露出適応状態::追従中(段(0.0)), 目標, 40);
    let 上限の移動量 = 露出の適応速度::既定値().補正段を下げる速さ().値() * 刻み幅;
    let mut 前 = 0.0;
    for 値 in &系列 {
        assert!(*値 <= 前, "単調に減っていない");
        assert!(*値 >= 目標.値() - 1.0e-6, "目標を跨いだ: {値}");
        assert!(前 - 値 <= 上限の移動量 + 1.0e-6, "1歩の移動が速さ×刻み幅を超えた: {}", 前 - 値);
        前 = *値;
    }
}

#[test]
fn 補正段を下げる向きと上げる向きで速さを使い分ける() {
    let 速度 = 露出の適応速度::既定値();
    let 一秒 = 秒::生成する(1.0);
    let 下げた = 次の適応状態を求める(露出適応状態::追従中(段(0.0)), 段(-10.0), 一秒, 速度).unwrap();
    let 上げた = 次の適応状態を求める(露出適応状態::追従中(段(0.0)), 段(10.0), 一秒, 速度).unwrap();
    assert_eq!(下げた, 露出適応状態::追従中(段(-速度.補正段を下げる速さ().値())));
    assert_eq!(上げた, 露出適応状態::追従中(段(速度.補正段を上げる速さ().値())));
    assert_ne!(速度.補正段を下げる速さ(), 速度.補正段を上げる速さ());
}

#[test]
fn 同じ固定刻みの列からは同じ系列が出る() {
    let 一度目 = 系列を作る(露出適応状態::追従中(段(-3.5)), 段(4.0), 60);
    let 二度目 = 系列を作る(露出適応状態::追従中(段(-3.5)), 段(4.0), 60);
    assert_eq!(一度目, 二度目);
}

#[test]
fn 系列は上下限の帯を出ない() {
    let 上下限 = 自動補正段の上下限::既定値();
    for 目標 in [上下限.下限(), 上下限.上限()] {
        for 値 in 系列を作る(露出適応状態::追従中(段(0.0)), 目標, 200) {
            assert!(値 >= 上下限.下限().値() && 値 <= 上下限.上限().値(), "帯を出た: {値}");
        }
    }
}

#[test]
fn 経過秒が負や非有限なら型付きの失敗になる() {
    for 経過 in [-0.1, f32::NAN, f32::INFINITY] {
        let 誤り = 次の適応状態を求める(露出適応状態::未初期化, 段(0.0), 秒::生成する(経過), 露出の適応速度::既定値());
        assert!(matches!(誤り, Err(自動露出エラー::値域外 { 項目: "経過秒", .. })), "{経過}を拒まなかった");
    }
}
