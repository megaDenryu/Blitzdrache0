//! 正の相対輝度: ヒストグラムのビンへ入れられる画素の明るさ。
//!
//! 0以下と非有限をこの型が拒むことで、ビンを決める段は有限の正の値だけを受ける。非有限を黙って端のビンへ
//! 写す経路が型の時点で無くなり、log2が定まらない画素は集計の区分が別枠で数える。

use super::{対数輝度, 自動露出エラー};

/// 不変条件: 有限かつ0より大きい。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 正の相対輝度(f32);

impl 正の相対輝度 {
    pub fn 生成する(値: f32) -> Result<Self, 自動露出エラー> {
        if !値.is_finite() || 値 <= 0.0 {
            return Err(自動露出エラー::値域外("正の相対輝度", 値));
        }
        Ok(Self(値))
    }

    /// 境界向けの生値取り出し。線形の境界値との比較だけがこの入口を使う。
    pub fn 値(&self) -> f32 {
        self.0
    }

    /// 対数の目盛へ写す。正の有限の値の2の対数は常に有限であるため、この変換は失敗しない。
    pub fn 対数輝度で表す(&self) -> 対数輝度 {
        対数輝度::生成する(self.0.log2()).unwrap_or_else(|誤り| panic!("正の有限の輝度から有限でない対数輝度が出た: {誤り}"))
    }
}
