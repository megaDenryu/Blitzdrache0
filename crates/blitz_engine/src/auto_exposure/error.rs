//! 自動露出の純関数が拒む入力と、導いた値が値域を外れた事実を表す型付きエラー。

use thiserror::Error;

use crate::sky::天空状態エラー;

#[derive(Debug, Clone, Copy, PartialEq, Error)]
pub enum 自動露出エラー {
    #[error("{項目}が値域を外れた: {値}")]
    値域外 { 項目: &'static str, 値: f32 },
    #[error("自動補正段の下限{下限}が上限{上限}を上回った")]
    上下限の順序が逆 { 下限: f32, 上限: f32 },
    #[error("ビンの添字がビンの本数以上だった: {0}")]
    ビンの添字が範囲外(u8),
    #[error("ヒストグラムのビンに画素が1つも無く、対数平均を定められない")]
    ビンへ入った画素が無い,
    #[error("割合の分母になる件数が0だった")]
    割合の分母が零件,
    #[error("露出補正段を作れなかった: {0}")]
    露出補正段を作れない(#[from] 天空状態エラー),
}

impl 自動露出エラー {
    pub(super) fn 値域外(項目: &'static str, 値: f32) -> Self {
        Self::値域外 { 項目, 値 }
    }
}
