//! 画素の相対輝度の定義と、その画素がヒストグラムのどの枠へ入るかの区分。
//!
//! 輝度は相対輝度Y = 0.2126R + 0.7152G + 0.0722B(BT.709の係数)で定める。単位はEVであり、輝度1.0が0EVである。
//! 範囲の制定に使った実測(`cargo xtask hdr-luminance`)と同じ定義であり、値が食い違うと制定した範囲が実測の
//! 分布と対応しなくなる。xtaskは外部依存を持たない方針を保つため同じ重みを写しとして持ち、
//! `cargo xtask conform`が両者の一致を機械的に見る。
//!
//! log2は正の値にしか定まらないため、画素は「正の輝度」「0以下」「非有限」の3つのどれか1つに必ず入る。
//! 0以下を番兵値でビンへ押し込まないのは、発光の無い完全な黒と最も暗いビンを区別するためである。

use super::{ビンの添字, ビンの添字を求める};

pub const 赤の重み: f32 = 0.2126;
pub const 緑の重み: f32 = 0.7152;
pub const 青の重み: f32 = 0.0722;

/// 1画素の輝度がヒストグラムのどの枠へ入るか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 輝度の区分 {
    ビンへ入る(ビンの添字),
    零以下,
    非有限,
}

/// 線形RGBから相対輝度を求める。
/// 前提: 受け取るのはGPUから読み戻した明るさの圧縮前のHDRカラーそのものであり、負や非有限を含みうる。
pub fn 相対輝度を求める(赤: f32, 緑: f32, 青: f32) -> f32 {
    赤 * 赤の重み + 緑 * 緑の重み + 青 * 青の重み
}

pub fn 画素を区分する(赤: f32, 緑: f32, 青: f32) -> 輝度の区分 {
    輝度を区分する(相対輝度を求める(赤, 緑, 青))
}

pub fn 輝度を区分する(輝度: f32) -> 輝度の区分 {
    if !輝度.is_finite() {
        return 輝度の区分::非有限;
    }
    if 輝度 <= 0.0 {
        return 輝度の区分::零以下;
    }
    輝度の区分::ビンへ入る(ビンの添字を求める(輝度.log2()))
}
