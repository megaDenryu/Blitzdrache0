//! 輝度ヒストグラム: 1フレームの画素を、制定した目盛のビンと2つの別枠へ数え上げた結果。
//!
//! 別枠を2つ持つのは、log2が定まらない画素をビンへ紛れ込ませないためである。0以下の画素と非有限の画素は
//! 対数平均の対象から外し、件数だけを報告へ載せる。

use super::{ビンの添字, ビン数, 全ビンの添字, 画素件数};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 輝度ヒストグラム {
    ビンの件数: [画素件数; ビン数],
    零以下の件数: 画素件数,
    非有限の件数: 画素件数,
}

impl 輝度ヒストグラム {
    pub fn 件数から生成する(
        ビンの件数: [画素件数; ビン数], 零以下の件数: 画素件数, 非有限の件数: 画素件数
    ) -> Self {
        Self {
            ビンの件数,
            零以下の件数,
            非有限の件数,
        }
    }

    pub fn ビンの件数(&self, 添字: ビンの添字) -> 画素件数 {
        self.ビンの件数[添字.配列の位置()]
    }

    /// 添字の昇順にビンを並べる。対数平均の総和をこの順で採ることが正本の定義の一部である。
    pub fn ビンごとの件数(&self) -> impl Iterator<Item = (ビンの添字, 画素件数)> + '_ {
        全ビンの添字().map(|添字| (添字, self.ビンの件数[添字.配列の位置()]))
    }

    /// ビンへ入った画素の総数。対数平均の母数である。
    pub fn ビンへ入った総数(&self) -> 画素件数 {
        self.ビンの件数.iter().fold(画素件数::零件(), |累計, 件数| 累計.足す(*件数))
    }

    /// 範囲より暗い画素が張り付く下端のビンの件数。上端の件数と合算しないのは、明部の飽和と暗部の潰れの
    /// どちらが起きているかを読めるようにするためである。
    pub fn 下端のビンの件数(&self) -> 画素件数 {
        self.ビンの件数[0]
    }

    /// 範囲より明るい画素が張り付く上端のビンの件数。
    pub fn 上端のビンの件数(&self) -> 画素件数 {
        self.ビンの件数[ビン数 - 1]
    }

    pub fn 零以下の件数(&self) -> 画素件数 {
        self.零以下の件数
    }

    pub fn 非有限の件数(&self) -> 画素件数 {
        self.非有限の件数
    }
}
