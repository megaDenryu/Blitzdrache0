//! 自動露出が今どの補正段に居るか。まだ1度もヒストグラムを読んでいない状態を枝として持つ。
//!
//! 未初期化を`Option`でも既定値でもなく枝で表すのは、「値がまだ無い」ことと「たまたま0EVである」ことを
//! 区別するためである。最初の有効なヒストグラムからは補間せずに目標をそのまま初期値にする
//! (起動直後に白飛び・黒潰れの1フレームを出さないため)。

use crate::sky::露出補正段;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 露出適応状態 {
    未初期化,
    追従中(露出補正段),
}

impl 露出適応状態 {
    /// 追従中の補正段。未初期化のときは値が無いことを呼び出し側へそのまま返す。
    pub fn 補正段(&self) -> Option<露出補正段> {
        match self {
            Self::未初期化 => None,
            Self::追従中(段) => Some(*段),
        }
    }
}
