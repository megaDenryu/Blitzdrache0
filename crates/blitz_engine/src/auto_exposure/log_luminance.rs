//! 対数輝度: 相対輝度を2の対数で表した値。単位はEV(2を底とする段数)であり、輝度1.0が0EVになる。
//!
//! 自動露出のヒストグラムの横軸と、そこから導く平均・中間灰がすべてこの量である。段数どうしの差だけが
//! 露出の補正量になるため、差を採る入口を型が持つ(引く向きの取り違えを名前で防ぐ)。

use super::自動露出エラー;
use crate::sky::露出補正段;

/// 不変条件: 有限である。0以下の相対輝度には対数が定まらないため、この型が作れるのは正の輝度からだけである。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 対数輝度(f32);

impl 対数輝度 {
    pub fn 生成する(値: f32) -> Result<Self, 自動露出エラー> {
        if !値.is_finite() {
            return Err(自動露出エラー::値域外("対数輝度", 値));
        }
        Ok(Self(値))
    }

    /// 境界向けの生値取り出し。GPUへ渡す値と、報告の書き出しだけがこの入口を使う。
    pub fn 値(&self) -> f32 {
        self.0
    }

    /// この明るさを写す先の明るさへ持ち上げるために要る露出の補正量。写す先が明るいほど正の段になる。
    pub fn 写すための補正段(&self, 写す先: Self) -> Result<露出補正段, 自動露出エラー> {
        Ok(露出補正段::生成する(写す先.0 - self.0)?)
    }
}
