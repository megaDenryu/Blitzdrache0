//! 画素を数えてヒストグラムを作る工程。受け取るのは1フレームぶんの画素の列、返すのは輝度ヒストグラムである。
//!
//! 値域の検証を持たない型で受け取るのは、この工程の入力がGPUから読み戻した明るさの圧縮前のHDRカラーそのものであり、
//! 負や非有限を含みうるためである。検証つきの値オブジェクトへ包むと、その検証が画素を捨てる判断になってしまう。
//! 3つの枠のどれへ入るかを決めるのは輝度の区分であり、この工程は数えるだけを担う。

use super::hdr_pixel::{明るさの圧縮前のHDR画素, 明るさの圧縮前の相対輝度};
use super::{ビン数, 画素を区分する, 画素件数, 輝度の区分, 輝度を区分する, 輝度ヒストグラム};

/// 線形RGBの画素列から集計する。
pub fn 画素列から集計する(画素列: impl IntoIterator<Item = 明るさの圧縮前のHDR画素>) -> 輝度ヒストグラム {
    区分列を数える(画素列.into_iter().map(画素を区分する))
}

/// 相対輝度の列から集計する。輝度を先に求めてある経路のための入口である。
pub fn 輝度列から集計する(輝度列: impl IntoIterator<Item = 明るさの圧縮前の相対輝度>) -> 輝度ヒストグラム {
    区分列を数える(輝度列.into_iter().map(輝度を区分する))
}

fn 区分列を数える(区分列: impl Iterator<Item = 輝度の区分>) -> 輝度ヒストグラム {
    let mut ビンの件数 = [画素件数::零件(); ビン数];
    let mut 零以下の件数 = 画素件数::零件();
    let mut 非有限の件数 = 画素件数::零件();
    for 区分 in 区分列 {
        match 区分 {
            輝度の区分::ビンへ入る(添字) => {
                let 位置 = 添字.配列の位置();
                ビンの件数[位置] = ビンの件数[位置].増やす();
            }
            輝度の区分::零以下 => 零以下の件数 = 零以下の件数.増やす(),
            輝度の区分::非有限 => 非有限の件数 = 非有限の件数.増やす(),
        }
    }
    輝度ヒストグラム::件数から生成する(ビンの件数, 零以下の件数, 非有限の件数)
}
