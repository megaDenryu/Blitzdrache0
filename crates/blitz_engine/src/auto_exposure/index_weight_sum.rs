//! 添字の重み付き総和: 切り詰めた窓に重なる件数を重みにした、ビンの添字の総和。
//!
//! 切り詰めた対数輝度の平均をこの整数1つから導くのは、ビンが代表する対数輝度が添字の1次式
//! (10×添字 - 891)÷64 で厳密に表せるためである。128項の浮動小数の総和を採ると、足す順と結合の順で
//! 最後の数ビットが動き、GPUの写しとの一致がその順に依存する。整数の加算は順にも結合にも依存しないため、
//! この総和はCPUとGPUで必ず同じ値になる。浮動小数が現れるのは、この整数から平均を作る境界より後だけである。
//!
//! 64ビットで持つのは、総和の上限が「窓の件数×最後のビンの添字」であり、32ビットでは約3380万画素の画面で
//! 飽和するためである(8K級の画面がその境目に当たる)。GPUの写しは32ビット2語で同じ整数を持つ。

use super::{ビンの添字, 画素件数};

/// 32ビット2語へ分けるときの、上位の語が表す重み。
const 上位の語の重み: f32 = 4_294_967_296.0;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 添字の重み付き総和(u64);

impl 添字の重み付き総和 {
    pub fn 零() -> Self {
        Self(0)
    }

    /// GPUの写しが持つ32ビット2語から組む。検収がGPUの観測を正本と比べるための入口である。
    pub fn 二語から生成する(上位の語: u32, 下位の語: u32) -> Self {
        Self(u64::from(上位の語) * (1 << 32) + u64::from(下位の語))
    }

    /// 1つのビンぶんを足す。重みは窓に重なった件数である。
    pub(super) fn 足す(&self, 重なり: 画素件数, 添字: ビンの添字) -> Self {
        Self(self.0 + u64::from(重なり.値()) * u64::from(添字.値()))
    }

    pub fn 値(&self) -> u64 {
        self.0
    }

    /// 平均を作るための実数。32ビット2語へ分けてから足すのは、GPUの写しが同じ2語から同じ順で作るためである。
    /// 上位の語への2の32乗の乗算は厳密であり、上位の語の変換・下位の語の変換・最後の加算が、CPUとGPUで同じ順に起こる。
    /// 注意: 変換そのものが丸めを持つ。2の24乗を超える語は整数のまま単精度へ収まらないため、語の変換の時点で丸められる。
    pub(super) fn 実数で表す(&self) -> f32 {
        let [下位0, 下位1, 下位2, 下位3, 上位0, 上位1, 上位2, 上位3] = self.0.to_le_bytes();
        let 下位 = 画素件数::生成する(u32::from_le_bytes([下位0, 下位1, 下位2, 下位3]));
        let 上位 = 画素件数::生成する(u32::from_le_bytes([上位0, 上位1, 上位2, 上位3]));
        上位.実数で表す() * 上位の語の重み + 下位.実数で表す()
    }
}
