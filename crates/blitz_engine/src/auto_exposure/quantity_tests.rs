//! EVの量の値オブジェクトの検査。値域の外を拒むことと、段の差を採る向きが取り違わないことを見る。

#![allow(clippy::unwrap_used)]

use super::histogram_scale::{
    ビンが覆う対数輝度の幅, 最初のビンが代表する対数輝度, 添字の平均が代表する対数輝度, 範囲の下端の対数輝度
};
use super::{ビンの添字, 対数輝度, 正の相対輝度, 添字の重み付き総和, 画素件数};

#[test]
fn 対数輝度と正の相対輝度は非有限を拒む() {
    for 値 in [f32::NAN, f32::INFINITY, f32::NEG_INFINITY] {
        assert!(対数輝度::生成する(値).is_err(), "対数輝度が{値}を拒まなかった");
        assert!(正の相対輝度::生成する(値).is_err(), "正の相対輝度が{値}を拒まなかった");
    }
}

#[test]
fn 正の相対輝度は0以下を拒み対数輝度は負を受ける() {
    assert!(正の相対輝度::生成する(0.0).is_err());
    assert!(正の相対輝度::生成する(-1.0).is_err());
    assert!(正の相対輝度::生成する(f32::MIN_POSITIVE).is_ok());
    assert!(対数輝度::生成する(-14.0).is_ok());
}

#[test]
fn 正の相対輝度から採る対数輝度は2の対数である() {
    assert_eq!(正の相対輝度::生成する(1.0).unwrap().対数輝度で表す().値(), 0.0);
    assert_eq!(正の相対輝度::生成する(0.25).unwrap().対数輝度で表す().値(), -2.0);
    assert!(正の相対輝度::生成する(f32::MIN_POSITIVE).unwrap().対数輝度で表す().値().is_finite());
}

#[test]
fn 写すための補正段は写す先が明るいほど正になる() {
    let 暗い = 正の相対輝度::生成する(0.25).unwrap().対数輝度で表す();
    let 明るい = 正の相対輝度::生成する(1.0).unwrap().対数輝度で表す();
    assert_eq!(暗い.写すための補正段(明るい).unwrap().値(), 2.0);
    assert_eq!(明るい.写すための補正段(暗い).unwrap().値(), -2.0);
}

#[test]
fn 最初のビンが代表する対数輝度は範囲の下端に幅の半分を足した値である() {
    assert_eq!(最初のビンが代表する対数輝度, 範囲の下端の対数輝度 + ビンが覆う対数輝度の幅 * 0.5);
}

#[test]
fn 添字の平均が代表する対数輝度は整数の添字ではビンの代表値と一致する() {
    for 位置 in [0u8, 1, 64, 127] {
        let 添字 = ビンの添字::生成する(位置).unwrap();
        assert_eq!(添字の平均が代表する対数輝度(f32::from(位置)), 添字.代表する対数輝度().値(), "添字{位置}");
    }
}

#[test]
fn 添字の重み付き総和は足す順に依らず同じ整数になる() {
    let 組 = [(3u8, 7u32), (100, 5), (64, 900_000)];
    let 昇順 = 組.iter().fold(添字の重み付き総和::零(), |和, (位置, 件数)| {
        和.足す(画素件数::生成する(*件数), ビンの添字::生成する(*位置).unwrap())
    });
    let 降順 = 組.iter().rev().fold(添字の重み付き総和::零(), |和, (位置, 件数)| {
        和.足す(画素件数::生成する(*件数), ビンの添字::生成する(*位置).unwrap())
    });
    assert_eq!(昇順, 降順);
    assert_eq!(昇順.値(), 3 * 7 + 100 * 5 + 64 * 900_000);
}

#[test]
fn 添字の重み付き総和は32ビット2語との往復で値を保つ() {
    let 大きい値 = 添字の重み付き総和::二語から生成する(3, 4_000_000_000);
    assert_eq!(大きい値.値(), 3 * (1u64 << 32) + 4_000_000_000);
    let 語から = 添字の重み付き総和::二語から生成する(0, 921_600 * 74);
    assert_eq!(語から.値(), 921_600 * 74);
}
