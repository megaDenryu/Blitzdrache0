//! 目標補正段の導出の検査。単一ビンでの期待値と、少数の極端な画素が平均を支配しないことを見る。

#![allow(clippy::unwrap_used)]

use super::{
    ビンの添字, ビン数, 最後のビンの添字, 画素件数, 目標中間灰, 目標補正段を導く, 自動補正段の上下限, 自動露出エラー, 輝度ヒストグラム
};

const 中間のビン: u8 = 64;

fn 添字(値: u8) -> ビンの添字 {
    ビンの添字::生成する(値).unwrap()
}

fn ヒストグラムを組む(組: &[(u8, u32)]) -> 輝度ヒストグラム {
    let mut ビンの件数 = [画素件数::零件(); ビン数];
    for (位置, 件数) in 組 {
        ビンの件数[usize::from(*位置)] = 画素件数::生成する(*件数);
    }
    輝度ヒストグラム::件数から生成する(ビンの件数, 画素件数::零件(), 画素件数::零件())
}

/// 件数で重み付けた、切り詰めをしない対数平均。切り詰めが効いていることの比較対象である。
fn 切り詰めない対数輝度の平均を求める(組: &[(u8, u32)]) -> f32 {
    let 総数: u32 = 組.iter().map(|(_, 件数)| 件数).sum();
    let 和: f32 = 組
        .iter()
        .map(|(位置, 件数)| 画素件数::生成する(*件数).実数で表す() * 添字(*位置).代表する対数輝度())
        .sum();
    和 / 画素件数::生成する(総数).実数で表す()
}

#[test]
fn 単一のビンに全画素が入るとそのビンの代表値から補正段が決まる() {
    let 結果 = 目標補正段を導く(
        &ヒストグラムを組む(&[(中間のビン, 10_000)]),
        目標中間灰::既定値(),
        自動補正段の上下限::既定値(),
    )
    .unwrap();
    assert!((結果.切り詰めた対数輝度の平均() - 添字(中間のビン).代表する対数輝度()).abs() < 1.0e-5);
    let 期待する段 = 目標中間灰::既定値().対数輝度で表す() - 添字(中間のビン).代表する対数輝度();
    assert!(
        (結果.目標補正段().値() - 期待する段).abs() < 1.0e-5,
        "目標補正段が期待と違う: {}",
        結果.目標補正段().値()
    );
}

#[test]
fn 少数の極端に明るい画素は切り詰めた平均を支配しない() {
    let 組 = [(中間のビン, 100_000), (最後のビンの添字, 900)];
    let 結果 = 目標補正段を導く(&ヒストグラムを組む(&組), 目標中間灰::既定値(), 自動補正段の上下限::既定値()).unwrap();
    assert!((結果.切り詰めた対数輝度の平均() - 添字(中間のビン).代表する対数輝度()).abs() < 1.0e-4);
    let 引かれ幅 = (切り詰めない対数輝度の平均を求める(&組) - 添字(中間のビン).代表する対数輝度()).abs();
    assert!(引かれ幅 > 0.05, "比較対象の切り詰めない平均が引かれていない: {引かれ幅}");
    assert!(結果.上端のビンの到達率().値() > 0.0);
    assert_eq!(結果.下端のビンの到達率().値(), 0.0);
}

#[test]
fn 少数の黒潰れした画素は切り詰めた平均を支配しない() {
    let 組 = [(0, 900), (中間のビン, 100_000)];
    let 結果 = 目標補正段を導く(&ヒストグラムを組む(&組), 目標中間灰::既定値(), 自動補正段の上下限::既定値()).unwrap();
    assert!((結果.切り詰めた対数輝度の平均() - 添字(中間のビン).代表する対数輝度()).abs() < 1.0e-4);
    let 引かれ幅 = (切り詰めない対数輝度の平均を求める(&組) - 添字(中間のビン).代表する対数輝度()).abs();
    assert!(引かれ幅 > 0.05, "比較対象の切り詰めない平均が引かれていない: {引かれ幅}");
    assert!(結果.下端のビンの到達率().値() > 0.0);
    assert_eq!(結果.上端のビンの到達率().値(), 0.0);
}

#[test]
fn 目標補正段は上下限へ収まる() {
    let 上下限 = 自動補正段の上下限::既定値();
    for 位置 in [0, 中間のビン, 最後のビンの添字] {
        let 結果 = 目標補正段を導く(&ヒストグラムを組む(&[(位置, 1_000)]), 目標中間灰::既定値(), 上下限).unwrap();
        assert!(結果.目標補正段().値() >= 上下限.下限().値(), "下限を下回った: {位置}");
        assert!(結果.目標補正段().値() <= 上下限.上限().値(), "上限を上回った: {位置}");
    }
}

#[test]
fn 暗い画面では上限へ張り付き明るい画面では下限へ張り付く() {
    let 上下限 = 自動補正段の上下限::既定値();
    let 暗い = 目標補正段を導く(&ヒストグラムを組む(&[(0, 1_000)]), 目標中間灰::既定値(), 上下限).unwrap();
    let 明るい = 目標補正段を導く(&ヒストグラムを組む(&[(最後のビンの添字, 1_000)]), 目標中間灰::既定値(), 上下限).unwrap();
    assert_eq!(暗い.目標補正段(), 上下限.上限());
    assert_eq!(明るい.目標補正段(), 上下限.下限());
}

#[test]
fn ビンに画素が1つも無ければ型付きの失敗になる() {
    let 誤り = 目標補正段を導く(&ヒストグラムを組む(&[]), 目標中間灰::既定値(), 自動補正段の上下限::既定値());
    assert_eq!(誤り, Err(自動露出エラー::ビンへ入った画素が無い));
}
