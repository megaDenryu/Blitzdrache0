//! 最終補正段の合成の検査。未初期化のあいだ自動補正段が0であることと、時刻別固定の枝が自動補正を1段も足さないことを見る。

#![allow(clippy::unwrap_used)]

use super::{最終補正段を合成する, 露出方式, 露出適応状態};
use crate::sky::露出補正段;

#[test]
fn 未初期化のあいだは芸術的バイアスだけになる() {
    let 方式 = 露出方式::ヒストグラム自動 {
        芸術的バイアス: 露出補正段::生成する(0.5).unwrap(),
    };
    assert_eq!(最終補正段を合成する(方式, 露出適応状態::未初期化).unwrap().値(), 0.5);
}

#[test]
fn 追従中は芸術的バイアスへ自動補正段を足す() {
    let 方式 = 露出方式::ヒストグラム自動 {
        芸術的バイアス: 露出補正段::生成する(0.5).unwrap(),
    };
    let 追従中 = 露出適応状態::追従中(露出補正段::生成する(2.0).unwrap());
    assert_eq!(最終補正段を合成する(方式, 追従中).unwrap().値(), 2.5);
}

#[test]
fn 時刻別固定の枝は自動補正を1段も足さない() {
    let 追従中 = 露出適応状態::追従中(露出補正段::生成する(2.0).unwrap());
    assert_eq!(最終補正段を合成する(露出方式::時刻別固定, 追従中).unwrap().値(), 0.0);
}
