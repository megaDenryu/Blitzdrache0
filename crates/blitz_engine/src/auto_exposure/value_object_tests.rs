//! 値オブジェクトの検証の検査。壊れた設定を作れないこと(拒むこと)を反証の形で見る。

#![allow(clippy::unwrap_used)]

use super::{
    ビン数, 最後のビンの添字, 画素の割合, 画素件数, 目標中間灰, 自動補正段の上下限, 自動露出エラー, 補正段毎秒, 露出の適応速度, 露出方式
};
use crate::sky::露出補正段;

#[test]
fn 上下限は下限が上限を上回る組を拒む() {
    assert_eq!(
        自動補正段の上下限::段の値から生成する(2.0, -2.0),
        Err(自動露出エラー::上下限の順序が逆 { 下限: 2.0, 上限: -2.0 })
    );
    assert!(自動補正段の上下限::段の値から生成する(-2.0, -2.0).is_ok());
}

#[test]
fn 上下限は非有限の端を拒む() {
    for 端 in [f32::NAN, f32::INFINITY, f32::NEG_INFINITY] {
        assert!(自動補正段の上下限::段の値から生成する(端, 6.0).is_err(), "下限{端}を拒まなかった");
        assert!(自動補正段の上下限::段の値から生成する(-4.0, 端).is_err(), "上限{端}を拒まなかった");
    }
}

#[test]
fn 上下限の既定値は現行の時刻別固定補正を帯へ含む() {
    let 上下限 = 自動補正段の上下限::既定値();
    for 現行の補正段 in [0.0, 2.0] {
        let 収めた = 上下限.収める(露出補正段::生成する(現行の補正段).unwrap());
        assert_eq!(収めた.値(), 現行の補正段, "昼夜の時刻別固定補正が帯の外にある");
    }
}

#[test]
fn 上下限は帯の外の段を端へ収める() {
    let 上下限 = 自動補正段の上下限::段の値から生成する(-1.0, 1.0).unwrap();
    assert_eq!(上下限.収める(露出補正段::生成する(5.0).unwrap()), 上下限.上限());
    assert_eq!(上下限.収める(露出補正段::生成する(-5.0).unwrap()), 上下限.下限());
}

#[test]
fn 目標中間灰は0以下と非有限を拒む() {
    for 値 in [0.0, -0.18, f32::NAN, f32::INFINITY] {
        assert!(目標中間灰::生成する(値).is_err(), "{値}を拒まなかった");
    }
    assert_eq!(目標中間灰::既定値().相対輝度().値(), 0.18);
    assert!((目標中間灰::既定値().対数輝度で表す().値() + 2.4739_f32).abs() < 1.0e-4);
}

#[test]
fn 適応速度は0以下と非有限を拒む() {
    for 値 in [0.0, -1.0, f32::NAN, f32::INFINITY] {
        assert!(補正段毎秒::生成する(値).is_err(), "{値}を拒まなかった");
    }
    let 既定 = 露出の適応速度::既定値();
    assert!(
        既定.補正段を下げる速さ().値() > 既定.補正段を上げる速さ().値(),
        "明順応が暗順応より遅い既定になっている"
    );
}

#[test]
fn 画素の割合は値域の外を拒む() {
    for 値 in [-0.1, 1.1, f32::NAN] {
        assert!(画素の割合::生成する(値).is_err(), "{値}を拒まなかった");
    }
    assert_eq!(画素の割合::生成する(0.25).unwrap().百分率(), 25.0);
    assert_eq!(
        画素の割合::件数の比から求める(画素件数::生成する(1), 画素件数::零件()),
        Err(自動露出エラー::割合の分母が零件)
    );
}

#[test]
fn 画素件数は16ビットを超える件数も実数へ正確に写す() {
    assert_eq!(画素件数::生成する(1_280 * 720).実数で表す(), 921_600.0);
    assert_eq!(画素件数::生成する(65_536).実数で表す(), 65_536.0);
    assert_eq!(画素件数::零件().増やす().足す(画素件数::生成する(2)), 画素件数::生成する(3));
}

#[test]
fn 露出方式は自動の枝だけが芸術的バイアスを持つ() {
    let バイアス = 露出補正段::生成する(0.5).unwrap();
    assert_eq!(露出方式::時刻別固定.芸術的バイアス(), None);
    assert_eq!(
        露出方式::ヒストグラム自動 {
            芸術的バイアス: バイアス
        }
        .芸術的バイアス(),
        Some(バイアス)
    );
}

#[test]
fn ビンの本数は8ビットの添字に収まる() {
    assert_eq!(ビン数, usize::from(最後のビンの添字) + 1);
    assert!(ビン数 <= usize::from(u8::MAX) + 1);
}
