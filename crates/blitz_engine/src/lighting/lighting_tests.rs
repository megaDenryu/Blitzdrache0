//! 既定ライティングの大域位置が世界全体の平行移動と同じ三軸ずらし量を受けることを検査する。

use blitz_math::{大域メートル, 大域ワールド位置};
use blitz_render::ライティング入力;

use super::既定ライティングを作る;

/// 既定ライティングの局所光源列は点光源1件である。その1件の位置を取り出す。
fn 先頭の点光源の位置(入力: &ライティング入力) -> 大域ワールド位置 {
    入力
        .局所光源列()
        .点光源を宣言の順に返す()
        .next()
        .unwrap_or_else(|| panic!("既定ライティングは点光源を1件持つ"))
        .位置()
}

#[test]
fn 点光源と影注視点へ同じ三軸ずらし量を足す() {
    let ずらし量 = 大域ワールド位置::生成する(大域メートル::生成する(1.0), 大域メートル::生成する(2.0), 大域メートル::生成する(3.0));
    let 入力 = 既定ライティングを作る(true, ずらし量);
    let 点光源 = 先頭の点光源の位置(&入力);
    let 影 = 入力.影注視点();
    assert_eq!([点光源.x().値(), 点光源.y().値(), 点光源.z().値()], [3.0, 4.0, 5.0]);
    assert_eq!([影.x().値(), 影.y().値(), 影.z().値()], [1.0, 2.0, 3.0]);
}
