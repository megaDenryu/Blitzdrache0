//! 既定ライティングの大域位置が世界全体の平行移動と同じ三軸オフセットを受けることを検査する。

use blitz_math::{大域メートル, 大域ワールド位置};

use super::既定ライティングを作る;

#[test]
fn 点光源と影注視点へ同じ三軸オフセットを足す() {
    let オフセット = 大域ワールド位置::生成する(大域メートル::生成する(1.0), 大域メートル::生成する(2.0), 大域メートル::生成する(3.0));
    let 入力 = 既定ライティングを作る(true, オフセット);
    let 点光源 = 入力.点光源位置();
    let 影 = 入力.影注視点();
    assert_eq!([点光源.x().値(), 点光源.y().値(), 点光源.z().値()], [3.0, 4.0, 5.0]);
    assert_eq!([影.x().値(), 影.y().値(), 影.z().値()], [1.0, 2.0, 3.0]);
}
