//! 天空状態からライティング入力への写しを検査する。夜に方向光が消えて影が落ちなくなること、
//! 下敷きの点光源と影の注視点が残ること、空ありの世界の既定時刻が既定ライティングと同じ色と強度になることを固定する。
//! 方向光の向きはレンダラー境界の外から読めないため、絵での確認は`cargo xtask sky-time`が担う。
#![allow(clippy::unwrap_used)]

use blitz_math::{大域ワールド位置, 大域秒};

use super::{天空状態をライティングへ写す, 既定ライティングを作る};
use crate::sky::{世界の空方針, 天空状態を導出する, 空と太陽の方針};
use crate::time::世界時刻;

fn 天空状態を作る(一日内秒: f64) -> crate::sky::天空状態 {
    let 時刻 = 世界時刻::生成する(大域秒::生成する(一日内秒)).unwrap();
    天空状態を導出する(時刻, &空と太陽の方針::既定値()).unwrap()
}

#[test]
fn 夜は方向光の強度が0になり影が落ちない() {
    let 昼 = 天空状態を作る(43_200.0);
    let 夜 = 天空状態を作る(75_600.0);
    assert!(昼.方向光強度().値() > 0.0);
    assert_eq!(夜.方向光強度().値(), 0.0);
    assert_eq!(夜.影の有効性(), crate::sky::影の有効性::無効);
    let 写した = 天空状態をライティングへ写す(既定ライティングを作る(true, 大域ワールド位置::原点()), &夜).unwrap();
    assert!(写した.ライトビュー射影を組み立てる(大域ワールド位置::原点()).is_ok());
}

#[test]
fn 下敷きの点光源と影の注視点は写しても変わらない() {
    let 下敷き = 既定ライティングを作る(true, 大域ワールド位置::原点());
    let 写した = 天空状態をライティングへ写す(下敷き, &天空状態を作る(21_600.0)).unwrap();
    assert_eq!(写した.局所光源列().件数(), 下敷き.局所光源列().件数());
    assert_eq!(先頭の点光源のx(&写した), 先頭の点光源のx(&下敷き));
    assert_eq!(写した.影注視点().y().値(), 下敷き.影注視点().y().値());
}

fn 先頭の点光源のx(入力: &blitz_render::ライティング入力) -> f64 {
    入力
        .局所光源列()
        .点光源を宣言の順に返す()
        .next()
        .unwrap_or_else(|| panic!("既定ライティングは点光源を1件持つ"))
        .位置()
        .x()
        .値()
}

#[test]
fn 空ありの既定時刻は既定ライティングと同じ色と強度になる() {
    let 世界の空方針::空あり { 空と太陽, 既定時刻 } = 世界の空方針::空ありの既定() else {
        panic!("空ありの既定は空ありになるはず");
    };
    let 状態 = 天空状態を導出する(既定時刻, &空と太陽).unwrap();
    assert_eq!(状態.方向光色().成分(), [1.0, 1.0, 1.0]);
    assert_eq!(状態.方向光強度().値(), 3.0);
    // 昼係数1.0での混色はf32の丸めを伴うため、既定ライティングの環境光0.03とは最下位桁で食い違う。
    assert!((状態.環境光強度().値() - 0.03).abs() < 1e-6);
    assert_eq!(状態.露出補正段().値(), 0.0);
}
