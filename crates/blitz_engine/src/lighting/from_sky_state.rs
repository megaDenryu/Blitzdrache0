//! 天空状態をレンダラーのライティング入力へ写す工程。受け取るのは世界が決めた下敷きのライティング入力と天空状態、
//! 返すのは方向光・環境光・影の落ち方だけを時刻の値へ置き換えたライティング入力である。
//! 点光源・影の正射影範囲・ライティングの有効は世界が決めたまま残すため、検収用の影範囲は時刻に動かされない。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「時刻の型」

use blitz_render::{
    ライティング入力, ライティング入力エラー, 光強度, 光色, 影の落ち方, 方向光入力, 環境光係数
};

use crate::sky::{天空状態, 影の有効性};

pub fn 天空状態をライティングへ写す(
    下敷き: ライティング入力,
    状態: &天空状態,
) -> Result<ライティング入力, ライティング入力エラー> {
    let 色成分 = 状態.方向光色().成分();
    let 色 = 光色::生成する(色成分[0], 色成分[1], 色成分[2])?;
    let 強度 = 光強度::生成する(状態.方向光強度().値())?;
    // 太陽方向は地表から太陽へ向かう単位ベクトルであり、方向光の向きはその逆である。
    let 太陽 = 状態.太陽方向().成分();
    let 方向光 = 方向光入力::生成する(-太陽[0], -太陽[1], -太陽[2], 色, 強度)?;
    let 環境光 = 環境光係数::生成する(状態.環境光強度().値())?;
    Ok(下敷き.光を差し替える(方向光, 環境光, 影の落ち方へ写す(状態.影の有効性())))
}

fn 影の落ち方へ写す(有効性: 影の有効性) -> 影の落ち方 {
    match 有効性 {
        影の有効性::有効 => 影の落ち方::落とす,
        影の有効性::無効 => 影の落ち方::落とさない,
    }
}
