use crate::streaming_chunk_world_fixture::{世界を作る, 後始末する};
use crate::streaming_coordinator_fixture::{常駐まで進める, 見積量を作る, 読込バイト数を測る, 起動する, 進める};
use crate::{ストリーミングメモリ量, チャンク座標, 予算判定};

fn 優先度退避を取り出す(判定: &予算判定) -> (チャンク座標, Vec<チャンク座標>) {
    let 予算判定::優先度退避 {
        最初の除外, 退避一覧
    } = 判定
    else {
        panic!("近い未収容チャンクがあるのに優先度退避にならなかった: {判定:?}");
    };
    (*最初の除外, 退避一覧.clone())
}

/// 中心が移ると足元が未収容になるが、使用量は上限ちょうどで超えていないため上限超過の退避では動かない。
/// この状態で退避しないと、外周に残った旧中心が上限を占め続けて足元が永久に描かれない。
#[test]
fn 一チャンク分の上限でも中心が移れば足元へ入れ替わる() {
    let 観測 = 読込バイト数を測る("priority_move_probe");
    let 見積 = 見積量を作る();
    // 読込中の1件と新規1件のRAMが同時には収まらない上限を作れる前提。VRAMを数えない読込中のあいだに隣まで収容されると筋書きが崩れる。
    assert!(観測 < 見積.ramバイト数 * 2, "観測が見積の2倍以上では1件だけを収容する上限を作れない");
    let (パス一覧, カタログ, 目録) = 世界を作る("priority_move", &[(0, 0), (1, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(観測, 見積.vramバイト数), 1);
    assert_eq!(常駐まで進める(&mut 調停, &カタログ, 50.0, 1), [チャンク座標::生成する(0, 0)]);

    let 移動 = 進める(&mut 調停, &カタログ, 150.0);
    let (最初の除外, 退避一覧) = 優先度退避を取り出す(移動.判定());
    assert_eq!(最初の除外, チャンク座標::生成する(1, 0));
    assert_eq!(退避一覧, [チャンク座標::生成する(0, 0)]);
    assert_eq!(移動.gpu資源解除待ち一覧(), [チャンク座標::生成する(0, 0)]);
    assert_eq!(移動.読込開始一覧(), []);

    // 解除待ちは実破棄が報告されるまでVRAMを数え続けるため、空けた分をこのフレームの収容へ使わない。退避も重ねない。
    let 破棄前 = 進める(&mut 調停, &カタログ, 150.0);
    assert_eq!(破棄前.読込開始一覧(), []);
    assert_eq!(破棄前.gpu資源解除待ち一覧(), []);

    assert!(調停.gpu資源の解除を報告する(チャンク座標::生成する(0, 0)).is_ok());
    assert_eq!(進める(&mut 調停, &カタログ, 150.0).読込開始一覧(), [チャンク座標::生成する(1, 0)]);
    後始末する(&パス一覧);
}

/// 中心が(2,0)のフレームだけ(1,0)が最も近い未収容になり、(3,0)のフレームでは(1,0)より遠い常駐が無くなる。
/// 優位が続かない入力では退避が起きず、同じ中心へ留まって初めて閾値へ届く。
#[test]
fn 境界の往復では近い未収容チャンクのための退避が起きない() {
    let 上限 = ストリーミングメモリ量::生成する(100_000, 見積量を作る().vramバイト数 * 3);
    let 座標一覧 = [(0, 0), (1, 0), (2, 0), (3, 0), (4, 0)];
    let (パス一覧, カタログ, 目録) = 世界を作る("priority_hysteresis", &座標一覧);
    let mut 調停 = 起動する(目録, 上限, 2);
    常駐まで進める(&mut 調停, &カタログ, 450.0, 3);

    for _回 in 0..6 {
        assert_eq!(進める(&mut 調停, &カタログ, 250.0).gpu資源解除待ち一覧(), []);
        assert_eq!(進める(&mut 調停, &カタログ, 350.0).gpu資源解除待ち一覧(), []);
    }

    let 留まった列: Vec<Vec<チャンク座標>> = (0..4)
        .map(|_回| 進める(&mut 調停, &カタログ, 250.0).gpu資源解除待ち一覧().to_vec())
        .collect();
    assert_eq!(留まった列, [vec![], vec![], vec![], vec![チャンク座標::生成する(4, 0)]]);
    後始末する(&パス一覧);
}

/// 上限を超えたフレームでも足元が未収容なら、上限超過を解く退避だけでは足元の余地が空かない。
/// 2つの発火が同じフレームで起きるとき、上限超過の分を先に計画し、収容余地の分をその残りへ重ねる。
#[test]
fn 上限超過の退避と収容余地の退避は同じフレームで重ならない() {
    let 上限 = ストリーミングメモリ量::生成する(100_000, 見積量を作る().vramバイト数 * 3 - 1);
    let 座標一覧 = [(0, 0), (1, -1), (1, 0), (1, 1)];
    let (パス一覧, カタログ, 目録) = 世界を作る("priority_with_overuse", &座標一覧);
    let mut 調停 = 起動する(目録, 上限, 1);
    常駐まで進める(&mut 調停, &カタログ, 250.0, 3);

    let 退避フレーム = 進める(&mut 調停, &カタログ, 50.0);
    let 予算判定::使用量超過による退避 {
        退避一覧, 退避後も超過
    } = 退避フレーム.判定()
    else {
        panic!("上限を超えているのに使用量超過による退避にならなかった: {:?}", 退避フレーム.判定());
    };
    // 上限超過を解く分が(1,-1)、足元(0,0)の余地を作る分が(1,1)である。同距離のタイブレークは番号の降順で決まる。
    assert_eq!(退避一覧, &[チャンク座標::生成する(1, -1), チャンク座標::生成する(1, 1)]);
    assert!(!退避後も超過);
    assert!(!退避一覧.contains(&チャンク座標::生成する(0, 0)));
    assert_eq!(退避フレーム.gpu資源解除待ち一覧(), 退避一覧.as_slice());

    // 重ねた退避は次のフレームで繰り返さない。実破棄が届くと足元が収容される。
    assert_eq!(進める(&mut 調停, &カタログ, 50.0).gpu資源解除待ち一覧(), []);
    for 座標 in [チャンク座標::生成する(1, -1), チャンク座標::生成する(1, 1)] {
        assert!(調停.gpu資源の解除を報告する(座標).is_ok());
    }
    assert_eq!(進める(&mut 調停, &カタログ, 50.0).読込開始一覧(), [チャンク座標::生成する(0, 0)]);
    後始末する(&パス一覧);
}
