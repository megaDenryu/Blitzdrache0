use crate::streaming_coordinator_fixture::{世界を作る, 後始末する, 準備完了を待つ, 起動する, 進める};
use crate::{ストリーミングメモリ量, チャンク座標, 予算判定};

#[test]
fn 目録にある座標だけを読み込み遠ざかるとcpuデータを捨てる() {
    let (パス一覧, カタログ, 目録) = 世界を作る("coordinator_load", &[(0, 0), (1, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(100_000, 100_000));
    let 初回 = 進める(&mut 調停, &カタログ, 50.0);
    assert_eq!(初回.読込開始一覧(), [チャンク座標::生成する(0, 0), チャンク座標::生成する(1, 0)]);
    assert_eq!(初回.判定(), 予算判定::全件収容);
    assert_eq!(初回.台帳登録数(), 2);

    let 準備完了一覧 = 準備完了を待つ(&mut 調停, &カタログ, 50.0, 2);
    assert_eq!(準備完了一覧, [チャンク座標::生成する(0, 0), チャンク座標::生成する(1, 0)]);

    // 目録に無い遠方のチャンクへ移ると必要集合が空になり、準備済みのCPUデータが即時に捨てられる。
    let 離脱 = 進める(&mut 調停, &カタログ, 100_050.0);
    assert_eq!(離脱.cpuデータ破棄一覧(), [チャンク座標::生成する(0, 0), チャンク座標::生成する(1, 0)]);
    assert_eq!(離脱.gpu資源解除待ち一覧(), []);
    assert_eq!(離脱.台帳登録数(), 0);
    後始末する(&パス一覧);
}

#[test]
fn 予算が足りないと外周を縮退させる() {
    let (パス一覧, カタログ, 目録) = 世界を作る("coordinator_budget", &[(0, 0), (1, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(300, 100_000));
    let 進行 = 進める(&mut 調停, &カタログ, 50.0);
    assert_eq!(進行.読込開始一覧(), [チャンク座標::生成する(0, 0)]);
    let 予算判定::縮退 {
        最初の除外,
        ram超過,
        vram超過,
    } = 進行.判定()
    else {
        panic!("予算が足りないのに縮退しなかった");
    };
    assert_eq!((最初の除外, ram超過, vram超過), (チャンク座標::生成する(1, 0), true, false));
    後始末する(&パス一覧);
}
