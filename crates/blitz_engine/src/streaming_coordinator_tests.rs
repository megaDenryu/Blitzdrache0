use crate::streaming_chunk_world_fixture::{世界を作る, 後始末する};
use crate::streaming_coordinator_fixture::{準備完了を待つ, 起動する, 進める};
use crate::{ストリーミングメモリ量, チャンク座標, 予算判定};

#[test]
fn 目録にある座標だけを読み込み遠ざかるとcpuデータを捨てる() {
    let (パス一覧, カタログ, 目録) = 世界を作る("coordinator_load", &[(0, 0), (1, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(100_000, 100_000), 1);
    let 初回 = 進める(&mut 調停, &カタログ, 50.0);
    assert_eq!(初回.読込開始一覧(), [チャンク座標::生成する(0, 0), チャンク座標::生成する(1, 0)]);
    assert_eq!(初回.判定(), &予算判定::全件収容);
    assert_eq!(初回.台帳登録数(), 2);

    let 準備完了一覧 = 準備完了を待つ(&mut 調停, &カタログ, 50.0, 2);
    assert_eq!(準備完了一覧, [チャンク座標::生成する(0, 0), チャンク座標::生成する(1, 0)]);

    // 目録に無い遠方のチャンクへ移ると必要集合が空になり、準備済みのCPUデータが即時に捨てられる。
    let 離脱 = 進める(&mut 調停, &カタログ, 100_050.0);
    assert_eq!(離脱.cpuデータ破棄一覧(), [チャンク座標::生成する(0, 0), チャンク座標::生成する(1, 0)]);
    assert_eq!(離脱.gpu資源解除待ち一覧(), []);
    assert_eq!(離脱.台帳登録数(), 0);
    後始末する(&パス一覧);
}

#[test]
fn gpu転送を報告すると常駐へ進み離脱で解除まで進む() {
    let (パス一覧, カタログ, 目録) = 世界を作る("coordinator_gpu", &[(0, 0), (1, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(100_000, 100_000), 1);
    for 座標 in 準備完了を待つ(&mut 調停, &カタログ, 50.0, 2) {
        let Ok(Some(_シーン)) = 調停.gpu転送のためにシーンデータを取り出す(座標) else {
            panic!("準備済みチャンクのシーンデータを取り出せなかった");
        };
        assert!(調停.gpu転送の完了を報告する(座標).is_ok());
    }
    // 常駐はCPUデータを持たずGPU資源だけを数えるため、RAMが0でVRAMが正になる。
    let 常駐後 = 進める(&mut 調停, &カタログ, 50.0);
    assert_eq!(常駐後.台帳登録数(), 2);
    assert_eq!(常駐後.使用量().ramバイト数, 0);
    assert!(常駐後.使用量().vramバイト数 > 0);

    let 離脱 = 進める(&mut 調停, &カタログ, 100_050.0);
    assert_eq!(離脱.gpu資源解除待ち一覧(), [チャンク座標::生成する(0, 0), チャンク座標::生成する(1, 0)]);
    for 座標 in 離脱.gpu資源解除待ち一覧() {
        assert!(調停.gpu資源の解除を報告する(*座標).is_ok());
    }
    assert_eq!(進める(&mut 調停, &カタログ, 100_050.0).台帳登録数(), 0);
    後始末する(&パス一覧);
}

#[test]
fn 準備済みでない座標の取り出しは値なしを返す() {
    let (パス一覧, カタログ, 目録) = 世界を作る("coordinator_absent", &[(0, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(100_000, 100_000), 1);
    進める(&mut 調停, &カタログ, 50.0);
    let Ok(None) = 調停.gpu転送のためにシーンデータを取り出す(チャンク座標::生成する(5, 5)) else {
        panic!("台帳に無い座標の取り出しが値なしにならなかった");
    };
    後始末する(&パス一覧);
}

#[test]
fn 予算が足りないと外周を縮退させる() {
    let (パス一覧, カタログ, 目録) = 世界を作る("coordinator_budget", &[(0, 0), (1, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(300, 100_000), 1);
    let 進行 = 進める(&mut 調停, &カタログ, 50.0);
    assert_eq!(進行.読込開始一覧(), [チャンク座標::生成する(0, 0)]);
    let 予算判定::縮退 {
        最初の除外,
        ram超過,
        vram超過,
    } = 進行.判定()
    else {
        panic!("予算が足りないのに縮退しなかった");
    };
    assert_eq!((*最初の除外, *ram超過, *vram超過), (チャンク座標::生成する(1, 0), true, false));
    後始末する(&パス一覧);
}
