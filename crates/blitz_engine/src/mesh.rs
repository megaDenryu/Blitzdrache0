//! 1辺1m・原点中心の立方体メッシュ。面ごとに異なる色を持つ。
//! 深度テストの機械検証のため、+Z面(白・手前)を先頭、-Z面(赤・奥)を末尾に描く
//! インデックス順で並べる（判断16）。

use blitz_render::頂点;

const 半径: f32 = 0.5;

struct 面定義 {
    角一覧: [[f32; 3]; 4],
    色: [f32; 3],
}

/// 立方体の頂点一覧・インデックス一覧を作る。
pub fn 立方体メッシュを作る() -> (Vec<頂点>, Vec<u32>) {
    let 面一覧 = 面一覧を作る();
    let mut 頂点一覧 = Vec::with_capacity(面一覧.len() * 4);
    let mut インデックス一覧 = Vec::with_capacity(面一覧.len() * 6);

    for 面 in &面一覧 {
        let 開始添字 = u32::try_from(頂点一覧.len())
            .unwrap_or_else(|_| panic!("頂点数がu32に収まらない"));
        for 角 in 面.角一覧 {
            頂点一覧.push(頂点 { 位置: 角, 色: 面.色 });
        }
        インデックス一覧.extend_from_slice(&[
            開始添字,
            開始添字 + 1,
            開始添字 + 2,
            開始添字,
            開始添字 + 2,
            開始添字 + 3,
        ]);
    }
    (頂点一覧, インデックス一覧)
}

/// 描画順は先頭(+Z・白)→末尾(-Z・赤)。深度テストが壊れていれば、後から描く赤が
/// 中央ピクセルで白を上書きし、スモークのピクセル判定が落ちる（判断16）。
fn 面一覧を作る() -> [面定義; 6] {
    [
        面定義 {
            角一覧: [[-半径, -半径, 半径], [半径, -半径, 半径], [半径, 半径, 半径], [-半径, 半径, 半径]],
            色: [0.9, 0.9, 0.9],
        },
        面定義 {
            角一覧: [[半径, -半径, 半径], [半径, -半径, -半径], [半径, 半径, -半径], [半径, 半径, 半径]],
            色: [0.1, 0.6, 0.9],
        },
        面定義 {
            角一覧: [[-半径, -半径, -半径], [-半径, -半径, 半径], [-半径, 半径, 半径], [-半径, 半径, -半径]],
            色: [0.9, 0.6, 0.1],
        },
        面定義 {
            角一覧: [[-半径, 半径, 半径], [半径, 半径, 半径], [半径, 半径, -半径], [-半径, 半径, -半径]],
            色: [0.2, 0.8, 0.3],
        },
        面定義 {
            角一覧: [[-半径, -半径, -半径], [半径, -半径, -半径], [半径, -半径, 半径], [-半径, -半径, 半径]],
            色: [0.7, 0.2, 0.8],
        },
        面定義 {
            角一覧: [[半径, -半径, -半径], [-半径, -半径, -半径], [-半径, 半径, -半径], [半径, 半径, -半径]],
            色: [0.9, 0.1, 0.1],
        },
    ]
}
