//! 距離から詳細段を決めるための設定。段を分ける距離の帯と、最も粗い段の2つを保持する。
//! 帯の検証と段番号の決定そのものは`lod_threshold`の核が持ち、この型は地形の語彙(大域メートル・地形詳細段)へ写す。

use blitz_math::大域メートル;
use blitz_render::地形詳細段;

use super::error::地形LODエラー;
use crate::lod_threshold::{段閾値エラー, 段閾値帯};

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 地形LOD選択設定 {
    帯: 段閾値帯,
    最粗段: 地形詳細段,
}

impl 地形LOD選択設定 {
    pub fn 生成する(
        基準距離: 大域メートル, ヒステリシス幅: 大域メートル, 最粗段: 地形詳細段
    ) -> Result<Self, 地形LODエラー> {
        let 帯 = 段閾値帯::生成する(基準距離.値(), ヒステリシス幅.値()).map_err(地形の語彙へ写す)?;
        Ok(Self { 帯, 最粗段 })
    }

    pub(super) fn 帯(self) -> 段閾値帯 {
        self.帯
    }

    pub(super) fn 最粗段(self) -> 地形詳細段 {
        self.最粗段
    }
}

/// 核が拒む理由は地形と個体で共通だが、呼び出し元が受け取るのは地形の語彙のエラーである。
/// 同じ破れを2つの型で表さないため、境界であるここ1箇所で写す。
fn 地形の語彙へ写す(誤り: 段閾値エラー) -> 地形LODエラー {
    match 誤り {
        段閾値エラー::基準距離不正 => 地形LODエラー::基準距離不正,
        段閾値エラー::ヒステリシス幅不正 => 地形LODエラー::ヒステリシス幅不正,
        段閾値エラー::ヒステリシス幅過大 => 地形LODエラー::ヒステリシス幅過大,
    }
}
