//! 距離から詳細段を決めるための設定。基準距離・ヒステリシス幅・最も粗い段の3つを検証して保持する。
//! ヒステリシス幅を基準距離の半分未満に限るのは、幅が半分以上だと隣り合う2つの境界の重なりが重複し、
//! 同じ距離が2段ぶん先の切替条件を同時に満たしうるためである。

use blitz_math::大域メートル;
use blitz_render::地形詳細段;

use super::error::地形LODエラー;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 地形LOD選択設定 {
    基準距離: 大域メートル,
    ヒステリシス幅: 大域メートル,
    最粗段: 地形詳細段,
}

impl 地形LOD選択設定 {
    pub fn 生成する(
        基準距離: 大域メートル, ヒステリシス幅: 大域メートル, 最粗段: 地形詳細段
    ) -> Result<Self, 地形LODエラー> {
        if !基準距離.値().is_finite() || 基準距離.値() <= 0.0 {
            return Err(地形LODエラー::基準距離不正);
        }
        if !ヒステリシス幅.値().is_finite() || ヒステリシス幅.値() < 0.0 {
            return Err(地形LODエラー::ヒステリシス幅不正);
        }
        if ヒステリシス幅.値() * 2.0 >= 基準距離.値() {
            return Err(地形LODエラー::ヒステリシス幅過大);
        }
        Ok(Self {
            基準距離,
            ヒステリシス幅,
            最粗段,
        })
    }

    /// 段番号nと段番号n+1を分ける距離。段番号0と1の境界が基準距離そのものである。
    pub(super) fn 境界距離(self, 細かい段: 地形詳細段) -> f64 {
        self.基準距離.値() * f64::from(細かい段.番号() + 1)
    }

    pub(super) fn ヒステリシス幅(self) -> f64 {
        self.ヒステリシス幅.値()
    }

    pub(super) fn 最粗段(self) -> 地形詳細段 {
        self.最粗段
    }

    /// ヒステリシスを使わない初回の段。距離を基準距離で割った商を最も粗い段で頭打ちにした値と一致する。
    /// 商を整数へ丸めず境界と順に比べるのは、最も粗い段が5段程度であり、比較の回数が丸めの縮小変換より短くて済むためである。
    pub(super) fn 初回の段(self, 距離: f64) -> 地形詳細段 {
        let mut 段 = 地形詳細段::最詳細();
        while 段 < self.最粗段 {
            let Some(次) = 段.一つ粗い段() else {
                break;
            };
            if 距離 < self.境界距離(段) {
                break;
            }
            段 = 次;
        }
        段
    }
}
