//! 緩和そのものの検査。距離から決まる段では隣接差が2以上になりにくいため、構成した入力を直接与えて連鎖の伝播と非常駐隣接の無視を確かめる。

#![allow(clippy::unwrap_used)]

use blitz_render::地形詳細段;

use super::relaxation::隣接差を緩和する;
use crate::チャンク座標;

fn 段(番号: u8) -> 地形詳細段 {
    地形詳細段::番号から生成する(番号)
}

fn 一列に並べる(段番号一覧: &[u8]) -> Vec<(チャンク座標, 地形詳細段)> {
    段番号一覧
        .iter()
        .enumerate()
        .map(|(位置, 番号)| {
            let x = i32::try_from(位置).unwrap();
            (チャンク座標::生成する(x, 0), 段(*番号))
        })
        .collect()
}

#[test]
fn 段差は連鎖して隣まで伝播する() {
    let mut 選択 = 一列に並べる(&[0, 4, 4, 4, 4]);
    隣接差を緩和する(&mut 選択);
    let 結果: Vec<u8> = 選択.iter().map(|(_, 段)| 段.番号()).collect();
    assert_eq!(結果, vec![0, 1, 2, 3, 4]);
}

#[test]
fn 段差が1以下の並びは変わらない() {
    let 元 = 一列に並べる(&[0, 1, 2, 3, 4]);
    let mut 選択 = 元.clone();
    隣接差を緩和する(&mut 選択);
    assert_eq!(選択, 元);
}

#[test]
fn 常駐しない隣接は制約にならない() {
    // Xが0と3の2つだけを常駐させる。互いに4近傍でないため、段差4がそのまま残る。
    let mut 選択 = vec![(チャンク座標::生成する(0, 0), 段(0)), (チャンク座標::生成する(3, 0), 段(4))];
    隣接差を緩和する(&mut 選択);
    assert_eq!(選択[1].1, 段(4));
}

#[test]
fn 縦横の両方向へ伝播する() {
    let mut 選択 = vec![
        (チャンク座標::生成する(0, 0), 段(0)),
        (チャンク座標::生成する(0, 1), 段(4)),
        (チャンク座標::生成する(1, 1), 段(4)),
    ];
    隣接差を緩和する(&mut 選択);
    assert_eq!(選択[1].1, 段(1), "Z方向の隣が1段だけ粗くなる");
    assert_eq!(選択[2].1, 段(2), "その隣がさらに1段だけ粗くなる");
}

/// 走査順を辞書順に固定しているため、入力の並びが同じなら結果も同じである。
#[test]
fn 同じ入力から同じ結果を得る() {
    let mut 一回目 = 一列に並べる(&[0, 4, 4, 2, 4]);
    let mut 二回目 = 一列に並べる(&[0, 4, 4, 2, 4]);
    隣接差を緩和する(&mut 一回目);
    隣接差を緩和する(&mut 二回目);
    assert_eq!(一回目, 二回目);
}
