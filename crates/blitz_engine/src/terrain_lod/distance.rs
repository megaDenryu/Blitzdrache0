//! 視点とチャンクの距離を求める工程。受け取るのは視点の大域位置とチャンク座標と格子の一辺、返すのはXZ平面での最短距離メートルである。
//! チャンクの大域包囲矩形との最短距離であるため、視点がチャンクの内側にあるとゼロになる。Yを見ないのは、チャンクの分割がXZ平面だけで行われ高さ方向に境界が無いためである。

use blitz_math::{大域メートル, 大域ワールド位置};

use crate::チャンク座標;

pub(super) fn チャンクとの最短距離(視点: 大域ワールド位置, 座標: チャンク座標, 一辺: 大域メートル) -> f64 {
    let 原点 = 座標.大域原点を求める(一辺);
    let x差 = 軸の距離(視点.x().値(), 原点.x().値(), 一辺.値());
    let z差 = 軸の距離(視点.z().値(), 原点.z().値(), 一辺.値());
    (x差 * x差 + z差 * z差).sqrt()
}

/// 1軸ぶんの区間外への距離。区間の内側なら0である。
fn 軸の距離(視点: f64, 区間の最小: f64, 一辺: f64) -> f64 {
    let 最大 = 区間の最小 + 一辺;
    if 視点 < 区間の最小 {
        区間の最小 - 視点
    } else if 視点 > 最大 {
        視点 - 最大
    } else {
        0.0
    }
}
