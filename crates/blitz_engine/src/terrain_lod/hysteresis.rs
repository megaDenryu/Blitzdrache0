//! 距離から詳細段を決める工程。受け取るのは前回の段と距離と設定、返すのは今回の段である。
//! 切替の規則そのものは`lod_threshold`の核が持ち、この工程は地形詳細段と段番号の間を写すことだけを担う。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「LOD」

use blitz_render::地形詳細段;

use super::selection_settings::地形LOD選択設定;

pub(super) fn 段を決める(前回: Option<地形詳細段>, 距離: f64, 設定: 地形LOD選択設定) -> 地形詳細段 {
    let 段番号 = 設定.帯().段番号を決める(前回.map(地形詳細段::番号), 距離, 設定.最粗段().番号());
    地形詳細段::番号から生成する(段番号)
}
