//! 距離から詳細段を決める工程。受け取るのは前回の段と距離と設定、返すのは今回の段である。
//! 粗い側へ切り替えるのは距離が境界にヒステリシス幅を足した値を超えたとき、細かい側へ戻すのは境界からヒステリシス幅を引いた値を下回ったときである。
//! 帯の内側では前回の段を保つため、境界をまたぐ往復で段が毎フレーム入れ替わらない。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「LOD」

use blitz_render::地形詳細段;

use super::selection_settings::地形LOD選択設定;

pub(super) fn 段を決める(前回: Option<地形詳細段>, 距離: f64, 設定: 地形LOD選択設定) -> 地形詳細段 {
    let Some(前回) = 前回 else {
        return 設定.初回の段(距離);
    };
    let 粗くした = 粗い側へ進める(前回, 距離, 設定);
    細かい側へ戻す(粗くした, 距離, 設定)
}

fn 粗い側へ進める(前回: 地形詳細段, 距離: f64, 設定: 地形LOD選択設定) -> 地形詳細段 {
    let mut 段 = 前回;
    while 段 < 設定.最粗段() {
        let Some(次) = 段.一つ粗い段() else {
            break;
        };
        if 距離 <= 設定.境界距離(段) + 設定.ヒステリシス幅() {
            break;
        }
        段 = 次;
    }
    段
}

fn 細かい側へ戻す(前回: 地形詳細段, 距離: f64, 設定: 地形LOD選択設定) -> 地形詳細段 {
    let mut 段 = 前回;
    while let Some(細かい段) = 段.一つ細かい段() {
        if 距離 >= 設定.境界距離(細かい段) - 設定.ヒステリシス幅() {
            break;
        }
        段 = 細かい段;
    }
    段
}
