//! 隣接するチャンクの段差を1以下へ引き下げる工程。受け取るのは辞書順に並んだ座標と段の一覧、書き換えるのはその段だけである。
//! 段は下げる方向にしか動かず0で止まるため、変化が無くなるまでの繰り返しは必ず終わる。走査順を辞書順に固定するため、同じ入力から常に同じ結果を得る。
//! 一覧に無い隣接は制約に数えない。常駐していないチャンクの段を要求すると、選択のために未読込のチャンクを読むことになるためである。
//! 参照: `_doc/設計/地形とカメラ相対描画.md`「LOD」

use std::collections::HashMap;

use blitz_render::地形詳細段;

use crate::チャンク座標;

pub(super) fn 隣接差を緩和する(選択: &mut [(チャンク座標, 地形詳細段)]) {
    let 位置表: HashMap<チャンク座標, usize> = 選択.iter().enumerate().map(|(添字, (座標, _))| (*座標, 添字)).collect();
    loop {
        let mut 変化した = false;
        for 添字 in 0..選択.len() {
            let (座標, 段) = 選択[添字];
            let Some(上限) = 上限を求める(選択, &位置表, 座標) else {
                continue;
            };
            if 段 > 上限 {
                選択[添字].1 = 上限;
                変化した = true;
            }
        }
        if !変化した {
            return;
        }
    }
}

/// 常駐する4近傍のうち最も細かい段の1つ粗い段。近傍が1つも常駐していなければ制約が無いため`None`を返す。
fn 上限を求める(
    選択: &[(チャンク座標, 地形詳細段)], 位置表: &HashMap<チャンク座標, usize>, 座標: チャンク座標
) -> Option<地形詳細段> {
    let 四近傍 = [
        チャンク座標::生成する(座標.x() - 1, 座標.z()),
        チャンク座標::生成する(座標.x() + 1, 座標.z()),
        チャンク座標::生成する(座標.x(), 座標.z() - 1),
        チャンク座標::生成する(座標.x(), 座標.z() + 1),
    ];
    四近傍
        .into_iter()
        .filter_map(|隣| 位置表.get(&隣).and_then(|添字| 選択.get(*添字)))
        .map(|(_, 段)| *段)
        .min()
        .and_then(地形詳細段::一つ粗い段)
}
