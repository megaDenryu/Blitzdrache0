//! 読込器の並列度と有界キュー容量を変更した起動の検査。

use super::*;
use crate::チャンク読込設定エラー;

#[test]
fn 読込設定は零を役割ごとの型付きエラーにする() {
    assert_eq!(チャンク読込設定::生成する(0, 1, 1), Err(チャンク読込設定エラー::ワーカー本数が零));
    assert_eq!(チャンク読込設定::生成する(1, 0, 1), Err(チャンク読込設定エラー::要求キュー容量が零));
    assert_eq!(チャンク読込設定::生成する(1, 1, 0), Err(チャンク読込設定エラー::完了キュー容量が零));
}

#[test]
fn 変更した本数と容量で二件を読み終える() {
    let Ok(設定) = チャンク読込設定::生成する(2, 2, 1) else {
        panic!("試験用の読込設定を作れなかった");
    };
    let 読込器 = 設定で起動する(設定);
    let mut パス一覧 = Vec::new();
    for 番号 in 0..2 {
        let シーン = 静的シーンを作る(vec![10, 20, 30, 255], 0.2);
        let Ok(バイト列) = シーンを実行時形式へ格納する(&シーン) else {
            panic!("試験用シーンを格納できなかった")
        };
        let (パス, id, カタログ) = 試験ファイルを作る(&format!("configured-{番号}"), &バイト列);
        assert!(
            読込器
                .読込を要求する(crate::チャンク座標::生成する(番号, 0), &id, &カタログ, リセット世代::最初を作る())
                .is_ok()
        );
        パス一覧.push(パス);
    }
    assert!(完了を待つ(&読込器).結果().is_ok());
    assert!(完了を待つ(&読込器).結果().is_ok());
    for パス in パス一覧 {
        assert!(std::fs::remove_file(パス).is_ok());
    }
}
