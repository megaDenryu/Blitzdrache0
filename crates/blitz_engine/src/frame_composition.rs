//! 既定シーンのフレーム構成をレンダラーの安全なフレームの処理位置の列として宣言する。

#[cfg(test)]
mod frame_composition_tests;

use blitz_render::{フレームの処理位置, フレーム構成, フレーム構成エラー};

/// 既定のフレームの処理位置の列。空とポスト処理は起動指定で抜ける任意の処理位置であり、抜いた構成でも順序は保たれる。
/// スキニング・布シミュレーション・粒子は素材の有無で中身が変わるが、処理位置そのものは常に宣言する
/// (素材が無ければパスが積まれない)。
const 既定のフレームの処理位置の列: [フレームの処理位置; 9] = [
    フレームの処理位置::スキニング,
    フレームの処理位置::布シミュレーション,
    フレームの処理位置::影,
    フレームの処理位置::シーン,
    フレームの処理位置::空,
    フレームの処理位置::粒子,
    フレームの処理位置::光のにじみと明るさの圧縮,
    フレームの処理位置::UI,
    フレームの処理位置::読み戻し,
];

pub fn 既定フレーム構成を作る(ポスト処理有効: bool, 空有効: bool) -> フレーム構成 {
    let 残す = |処理位置: &フレームの処理位置| match 処理位置 {
        フレームの処理位置::空 => 空有効,
        フレームの処理位置::光のにじみと明るさの圧縮 => ポスト処理有効,
        _ => true,
    };
    let 処理位置の列: Vec<フレームの処理位置> = 既定のフレームの処理位置の列.into_iter().filter(残す).collect();
    定数の検証結果から値を取り出す(フレーム構成::生成する(&処理位置の列))
}

fn 定数の検証結果から値を取り出す(結果: Result<フレーム構成, フレーム構成エラー>) -> フレーム構成 {
    結果.unwrap_or_else(|誤り| panic!("既定フレーム構成が不正だった: {誤り}"))
}
