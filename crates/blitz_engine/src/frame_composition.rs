//! 既定シーンのフレーム構成をレンダラーの安全な段階列として宣言する。

use blitz_render::{フレーム構成, フレーム構成エラー, フレーム段階};

pub fn 既定フレーム構成を作る(ポスト処理有効: bool) -> フレーム構成 {
    let ポストあり = [
        フレーム段階::スキニング,
        フレーム段階::布シミュレーション,
        フレーム段階::影,
        フレーム段階::シーン,
        フレーム段階::粒子,
        フレーム段階::ブルームとトーンマップ,
        フレーム段階::UI,
        フレーム段階::読み戻し,
    ];
    let ポストなし = [
        フレーム段階::スキニング,
        フレーム段階::布シミュレーション,
        フレーム段階::影,
        フレーム段階::シーン,
        フレーム段階::粒子,
        フレーム段階::UI,
        フレーム段階::読み戻し,
    ];
    let 結果 = if ポスト処理有効 {
        フレーム構成::生成する(&ポストあり)
    } else {
        フレーム構成::生成する(&ポストなし)
    };
    確定値(結果)
}

fn 確定値(結果: Result<フレーム構成, フレーム構成エラー>) -> フレーム構成 {
    結果.unwrap_or_else(|誤り| panic!("既定フレーム構成が不正だった: {誤り}"))
}
