//! 既定シーンのフレーム構成をレンダラーの安全な段階列として宣言する。

#[cfg(test)]
mod frame_composition_tests;

use blitz_render::{フレーム構成, フレーム構成エラー, フレーム段階};

/// 既定の段階列。空とポスト処理は起動指定で抜ける任意の段階であり、抜いた構成でも順序は保たれる。
/// スキニング・布シミュレーション・粒子は素材の有無で中身が変わるが、段階そのものは常に宣言する
/// (素材が無ければパスが積まれない)。
const 既定の段階列: [フレーム段階; 9] = [
    フレーム段階::スキニング,
    フレーム段階::布シミュレーション,
    フレーム段階::影,
    フレーム段階::シーン,
    フレーム段階::空,
    フレーム段階::粒子,
    フレーム段階::光のにじみと明るさの圧縮,
    フレーム段階::UI,
    フレーム段階::読み戻し,
];

pub fn 既定フレーム構成を作る(ポスト処理有効: bool, 空有効: bool) -> フレーム構成 {
    let 残す = |段階: &フレーム段階| match 段階 {
        フレーム段階::空 => 空有効,
        フレーム段階::光のにじみと明るさの圧縮 => ポスト処理有効,
        _ => true,
    };
    let 段階列: Vec<フレーム段階> = 既定の段階列.into_iter().filter(残す).collect();
    定数の検証結果から値を取り出す(フレーム構成::生成する(&段階列))
}

fn 定数の検証結果から値を取り出す(結果: Result<フレーム構成, フレーム構成エラー>) -> フレーム構成 {
    結果.unwrap_or_else(|誤り| panic!("既定フレーム構成が不正だった: {誤り}"))
}
