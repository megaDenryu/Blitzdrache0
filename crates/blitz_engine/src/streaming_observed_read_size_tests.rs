use crate::streaming_chunk_world_fixture::{世界を作る, 後始末する};
use crate::streaming_coordinator_fixture::{準備完了を待つ, 見積量を作る, 読込バイト数を測る, 起動する, 進める};
use crate::{ストリーミングメモリ量, チャンク座標, 観測済み読込量};

/// 見積は版付きファイルの固定部分を数えないため、観測より必ず小さい。この差が読込後の上限超過を生む。
#[test]
fn 読込の観測は見積を上回る() {
    assert!(読込バイト数を測る("observed_probe_compare") > 見積量を作る().ramバイト数);
}

/// 観測は読込器が返したファイル長であり、カタログの見積が数える分をすべて含むとは限らない。
/// 小さい観測で無条件に置き換えると過小計上へ戻るため、大きいほうへそろえる。
#[test]
fn 観測が見積より小さい座標では見積を保つ() {
    let 座標 = チャンク座標::生成する(3, 4);
    let 見積 = ストリーミングメモリ量::生成する(500, 700);
    let mut 観測 = 観測済み読込量::空を作る();
    観測.記録する(座標, 400);
    assert_eq!(観測.見積を補正する(座標, 見積), 見積);
    観測.記録する(座標, 900);
    assert_eq!(観測.見積を補正する(座標, 見積), ストリーミングメモリ量::生成する(900, 700));
}

#[test]
fn 一度読んだ座標は再収容の判定に観測を使う() {
    let 観測 = 読込バイト数を測る("observed_probe_reentry");
    let 見積 = 見積量を作る().ramバイト数;
    let (パス一覧, カタログ, 目録) = 世界を作る("observed_reentry", &[(0, 0), (1, 0)]);
    // 見積2件はちょうど収まり、観測1件と見積1件は収まらない上限。観測を覚えていなければ2件目を再び収容してしまう。
    let 上限 = ストリーミングメモリ量::生成する(観測 + 見積 - 1, 100_000);
    let mut 調停 = 起動する(目録, 上限, 1);
    let 初回 = 進める(&mut 調停, &カタログ, 50.0);
    assert_eq!(初回.読込開始一覧(), [チャンク座標::生成する(0, 0), チャンク座標::生成する(1, 0)]);
    準備完了を待つ(&mut 調停, &カタログ, 50.0, 2);

    // 目録に無い遠方へ移ると台帳から記録が消えるが、読込量の観測は残る。
    進める(&mut 調停, &カタログ, 100_050.0);
    assert_eq!(調停.台帳登録数(), 0);
    assert_eq!(調停.観測済み読込量件数(), 2);

    // 見積のままなら2件とも収容できる上限だが、観測を使うため中心1件だけになる。
    let 再訪 = 進める(&mut 調停, &カタログ, 50.0);
    assert_eq!(再訪.読込開始一覧(), [チャンク座標::生成する(0, 0)]);
    // 読み直しても2件目は観測で除外され続けるため、収容と超過の往復が起きない。
    for _回 in 0..3 {
        let 続き = 進める(&mut 調停, &カタログ, 50.0);
        assert_eq!(続き.読込開始一覧(), []);
        assert_eq!(続き.gpu資源解除待ち一覧(), []);
    }
    assert_eq!(調停.台帳登録数(), 1);
    後始末する(&パス一覧);
}
