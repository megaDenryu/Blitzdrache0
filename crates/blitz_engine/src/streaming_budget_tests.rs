use blitz_math::{大域メートル, 大域ワールド位置};

use crate::{
    ストリーミングメモリ量, ストリーミング予算, ストリーミング予算エラー, チャンク予算候補, チャンク格子, チャンク要求, 予算判定
};

#[test]
fn 中心優先の接頭辞だけを予算内へ収容する() {
    let 要求一覧 = 要求を作る();
    let 候補一覧: Vec<_> = 要求一覧
        .iter()
        .map(|要求| チャンク予算候補::生成する(*要求, ストリーミングメモリ量::生成する(40, 30)))
        .collect();
    let 予算 = 予算を作る(100, 100);
    let Ok(結果) = 予算.適用する(ストリーミングメモリ量::default(), &候補一覧) else {
        panic!("予算を適用できなかった");
    };
    assert_eq!(結果.収容一覧(), &候補一覧[..2]);
    assert_eq!(結果.除外一覧().len(), 7);
    assert_eq!(結果.使用量(), ストリーミングメモリ量::生成する(80, 60));
    assert_eq!(
        結果.判定(),
        &予算判定::縮退 {
            最初の除外: 要求一覧[2].座標(),
            ram超過: true,
            vram超過: false,
        }
    );
}

#[test]
fn 収まらない候補以降の小さい外周も飛び越して収容しない() {
    let 要求一覧 = 要求を作る();
    let 候補一覧 = [
        チャンク予算候補::生成する(要求一覧[0], ストリーミングメモリ量::生成する(60, 10)),
        チャンク予算候補::生成する(要求一覧[1], ストリーミングメモリ量::生成する(50, 10)),
        チャンク予算候補::生成する(要求一覧[2], ストリーミングメモリ量::生成する(1, 1)),
    ];
    let Ok(結果) = 予算を作る(100, 100).適用する(ストリーミングメモリ量::default(), &候補一覧) else {
        panic!("接頭辞予算を適用できなかった");
    };
    assert_eq!(結果.収容一覧(), [候補一覧[0]]);
    assert_eq!(結果.除外一覧(), [要求一覧[1].座標(), 要求一覧[2].座標()]);
}

#[test]
fn 全件収容と現在使用量超過を区別する() {
    let 要求一覧 = 要求を作る();
    let 候補 = [チャンク予算候補::生成する(
        要求一覧[0],
        ストリーミングメモリ量::生成する(10, 20),
    )];
    let 予算 = 予算を作る(100, 100);
    let Ok(結果) = 予算.適用する(ストリーミングメモリ量::生成する(5, 5), &候補) else {
        panic!("全件収容の予算を適用できなかった");
    };
    assert_eq!(結果.判定(), &予算判定::全件収容);
    assert!(matches!(
        予算.適用する(ストリーミングメモリ量::生成する(101, 0), &候補),
        Err(ストリーミング予算エラー::現在使用量超過)
    ));
}

fn 予算を作る(ram: u64, vram: u64) -> ストリーミング予算 {
    match ストリーミング予算::生成する(ストリーミングメモリ量::生成する(ram, vram)) {
        Ok(予算) => 予算,
        Err(誤り) => panic!("試験用予算を作れなかった: {誤り}"),
    }
}

pub(super) fn 要求を作る() -> Vec<チャンク要求> {
    let 格子 = match チャンク格子::生成する(大域メートル::生成する(100.0)) {
        Ok(格子) => 格子,
        Err(誤り) => panic!("試験用格子を作れなかった: {誤り}"),
    };
    let 位置 = 大域ワールド位置::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(0.0), 大域メートル::生成する(0.0));
    match 格子.必要集合を計算する(位置, 1) {
        Ok(要求) => 要求,
        Err(誤り) => panic!("試験用要求を作れなかった: {誤り}"),
    }
}
