use blitz_render::フレームの処理位置;

use crate::既定フレーム構成を作る;

#[test]
fn ポスト処理と空の有無だけを切り替える() {
    let 全部あり = 既定フレーム構成を作る(true, true);
    let ポストなし = 既定フレーム構成を作る(false, true);
    let 空なし = 既定フレーム構成を作る(true, false);

    assert!(全部あり.含むか(フレームの処理位置::光のにじみと明るさの圧縮));
    assert!(!ポストなし.含むか(フレームの処理位置::光のにじみと明るさの圧縮));
    assert!(ポストなし.含むか(フレームの処理位置::空));
    assert!(全部あり.含むか(フレームの処理位置::空));
    assert!(!空なし.含むか(フレームの処理位置::空));
    assert!(空なし.含むか(フレームの処理位置::光のにじみと明るさの圧縮));
    for 構成 in [全部あり, ポストなし, 空なし] {
        assert!(構成.含むか(フレームの処理位置::影));
        assert!(構成.含むか(フレームの処理位置::シーン));
    }
}
