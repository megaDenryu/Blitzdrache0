//! 子形状識別子: 1つの衝突対象の中で子形状を指す番号。
//!
//! 裸のu32で持たないのは、描画対象IDや個体の番号といった同じ形の数が周りに並んでおり、どれを渡しても型が通るためである。
//! 番号の由来は建物を組み立てたときに部品を据えた順であり、同じ入力からは同じ番号が出る。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断10: 衝突形状が宣言できる属性」

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct 子形状識別子(u32);

impl 子形状識別子 {
    pub fn 番号から生成する(番号: u32) -> Self {
        Self(番号)
    }

    pub fn 番号を返す(&self) -> u32 {
        self.0
    }
}
