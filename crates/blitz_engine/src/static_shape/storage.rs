//! チャンクごとの静的物理形状の保管: 読み込み済みチャンクの静的物理形状を座標で参照できる形で持つ型。
//!
//! 可変の対応表を型の中へ閉じるのは、載せる・外す・空にするの3つ以外の経路で中身が変わらないようにするためである。
//! 注意: 保管する座標の集合は、チャンクが描かれている区間を必ず包含する。描かれているのに当たらない瞬間を作らないためであり、
//! 当たるのに描かれていない余白は安全側として許す。出入りを決める規律は`streaming`の調停が持つ。
//!
//! 対応表を座標で整列した木にするのは、空間索引が読込済みチャンクを座標の昇順に1つずつ辿るためである。整列しない
//! 対応表では反復の順が実行ごとに変わり、候補の並びが入力だけで決まらなくなる。問い合わせのたびに座標を集めて
//! 並べ替えれば確保が起きるため、順序を保つ側を対応表に持たせる。
//! 参照: `_doc/設計/チャンクストリーミング.md`「状態台帳」

use std::collections::BTreeMap;

use super::chunk_shapes::チャンクの静的物理形状;
use crate::チャンク座標;

/// 読み込み済みチャンクの静的物理形状を、チャンク座標から参照できる形で持つ対応表。
#[derive(Debug)]
pub struct チャンクごとの静的物理形状の保管 {
    座標ごとの形状: BTreeMap<チャンク座標, チャンクの静的物理形状>,
}

impl チャンクごとの静的物理形状の保管 {
    /// 1件も載っていない保管。調停の起動とリセットが作る。
    pub fn 空を作る() -> Self {
        Self {
            座標ごとの形状: BTreeMap::new(),
        }
    }

    /// 同じ座標へ2度載せると後から載せたもので置き換える。読み直したチャンクの形状が古いものと混ざらないためである。
    pub fn 載せる(&mut self, 座標: チャンク座標, 形状: チャンクの静的物理形状) {
        self.座標ごとの形状.insert(座標, 形状);
    }

    /// 載っていない座標を外しても失敗にしない。解除の報告は台帳に無い座標についても届きうるためである。
    pub fn 外す(&mut self, 座標: チャンク座標) {
        self.座標ごとの形状.remove(&座標);
    }

    /// 載っている形状をすべて外す。実行時アセット一式の差し替えが呼ぶ。
    pub fn 空にする(&mut self) {
        self.座標ごとの形状.clear();
    }

    /// その座標に載っている形状。載っていなければ値なしを返す。
    pub fn 座標で参照する(&self, 座標: チャンク座標) -> Option<&チャンクの静的物理形状> {
        self.座標ごとの形状.get(&座標)
    }

    /// 載っている形状を、チャンク座標の昇順に座標と組で数え上げる。空間索引の1段目がこれを辿る。
    pub fn 座標の昇順で数え上げる(&self) -> impl Iterator<Item = (チャンク座標, &チャンクの静的物理形状)> {
        self.座標ごとの形状.iter().map(|(座標, 形状)| (*座標, 形状))
    }

    /// 形状が載っている座標の件数。
    pub fn 登録数(&self) -> usize {
        self.座標ごとの形状.len()
    }
}
