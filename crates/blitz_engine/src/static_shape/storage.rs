//! チャンクごとの静的物理形状の保管: 読み込み済みチャンクの静的物理形状を座標で引ける形で持つ型。
//!
//! 可変の対応表を型の中へ閉じるのは、載せる・外す・空にするの3つ以外の経路で中身が変わらないようにするためである。
//! 注意: 保管する座標の集合は、チャンクが描かれている区間を必ず包含する。描かれているのに当たらない瞬間を作らないためであり、
//! 当たるのに描かれていない余白は安全側として許す。出入りを決める規律は`streaming`の調停が持つ。
//! 参照: `_doc/設計/チャンクストリーミング.md`「状態台帳」

use std::collections::HashMap;

use super::chunk_shapes::チャンクの静的物理形状;
use crate::チャンク座標;

#[derive(Debug)]
pub struct チャンクごとの静的物理形状の保管 {
    座標ごとの形状: HashMap<チャンク座標, チャンクの静的物理形状>,
}

impl チャンクごとの静的物理形状の保管 {
    pub fn 空を作る() -> Self {
        Self {
            座標ごとの形状: HashMap::new(),
        }
    }

    /// 同じ座標へ2度載せると後から載せたもので置き換える。読み直したチャンクの形状が古いものと混ざらないためである。
    pub fn 載せる(&mut self, 座標: チャンク座標, 形状: チャンクの静的物理形状) {
        self.座標ごとの形状.insert(座標, 形状);
    }

    /// 載っていない座標を外しても失敗にしない。解除の報告は台帳に無い座標についても届きうるためである。
    pub fn 外す(&mut self, 座標: チャンク座標) {
        self.座標ごとの形状.remove(&座標);
    }

    pub fn 空にする(&mut self) {
        self.座標ごとの形状.clear();
    }

    pub fn 座標で引く(&self, 座標: チャンク座標) -> Option<&チャンクの静的物理形状> {
        self.座標ごとの形状.get(&座標)
    }

    pub fn 登録数(&self) -> usize {
        self.座標ごとの形状.len()
    }
}
