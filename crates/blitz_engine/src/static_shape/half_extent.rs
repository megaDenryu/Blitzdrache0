//! 直方体の軸ごとの半分の長さ: 直方体の中心から面までの、その直方体自身の3軸に沿った長さ。
//!
//! 位置でも変位でもなく長さの組で持つのは、この量が座標系の原点に依らず、回転を掛けても変わらないためである。
//! 負の値は面の裏返しであり、重なりの判定を無意味にするため生成が拒む。0は許す。厚みの無い板として据えた部品がありうるためである。

use blitz_math::メートル;

use super::error::{軸名一覧, 静的物理形状エラー};

/// 直方体の中心から面までの、その直方体自身の3軸に沿った長さ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 直方体の軸ごとの半分の長さ {
    成分: [メートル; 3],
}

impl 直方体の軸ごとの半分の長さ {
    /// 負の長さと有限でない長さを型付きエラーで拒む。
    pub fn 生成する(成分: [メートル; 3]) -> Result<Self, 静的物理形状エラー> {
        for (軸, 値) in 軸名一覧.into_iter().zip(成分) {
            if !値.値().is_finite() || 値.値() < 0.0 {
                return Err(静的物理形状エラー::半分の長さが負か非有限 { 軸 });
            }
        }
        Ok(Self { 成分 })
    }

    /// 直方体自身の東西の軸に沿った半分の長さ。
    pub fn x(&self) -> メートル {
        self.成分[0]
    }

    /// 直方体自身の天頂の軸に沿った半分の長さ。
    pub fn y(&self) -> メートル {
        self.成分[1]
    }

    /// 直方体自身の南北の軸に沿った半分の長さ。
    pub fn z(&self) -> メートル {
        self.成分[2]
    }
}
