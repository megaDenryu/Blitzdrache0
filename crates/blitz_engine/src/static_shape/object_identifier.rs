//! 衝突対象の安定識別子: チャンクの中で1つの静的な衝突対象を指す文字列。
//!
//! 番号でなく文字列で持つのは、問い合わせの答えを制作時のデータへ辿れるようにするためである。文字列の由来は建物をチャンクへ
//! 置いた配置の識別子であり、正準化はソースを読む地点(`blitz_asset_compiler`の`配置識別子`)が済ませている。
//! この型は正準化済みの値を受けるだけであり、自分では文字列を変えない。変えると重複の判定を済ませた文字列と食い違う。
//! 焼き直しで並びが変わっても文字列は変わらない。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断10: 衝突形状が宣言できる属性」

use std::fmt;

use super::error::静的物理形状エラー;

/// チャンクの中で1つの静的な衝突対象を指す、正準化済みの文字列。
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct 衝突対象の安定識別子 {
    文字列: String,
}

impl 衝突対象の安定識別子 {
    /// 空の文字列と、正準でない文字列(前後に空白が付いたもの)を拒む。落とさずに拒むのは、正準化がここより上流で
    /// 済んでおり、ここで黙って落とすと重複の判定を通った文字列と焼き上がりの文字列が食い違うためである。
    pub fn 生成する(文字列: &str) -> Result<Self, 静的物理形状エラー> {
        if 文字列.is_empty() {
            return Err(静的物理形状エラー::安定識別子が空);
        }
        if 文字列 != 文字列.trim() {
            return Err(静的物理形状エラー::安定識別子が前後に空白を持つ);
        }
        Ok(Self { 文字列: 文字列.to_string() })
    }

    /// 包んでいる文字列そのもの。実行時形式へ書き出す境界と問い合わせの答えが読む。
    pub fn 文字列(&self) -> &str {
        &self.文字列
    }
}

impl fmt::Display for 衝突対象の安定識別子 {
    fn fmt(&self, 出力: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(出力, "{}", self.文字列)
    }
}
