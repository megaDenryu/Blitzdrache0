//! 衝突対象の安定識別子: チャンクの中で1つの静的な衝突対象を指す綴り。
//!
//! 番号でなく綴りで持つのは、問い合わせの答えを制作時のデータへ辿れるようにするためである。綴りの由来は建物をチャンクへ
//! 置いた配置の識別子であり、正準化はソースを読む地点(`blitz_asset_compiler`の`配置識別子`)が済ませている。
//! この型は正準化済みの値を受けるだけであり、自分では綴りを変えない。変えると重複の判定を済ませた綴りと食い違う。
//! 焼き直しで並びが変わっても綴りは変わらない。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断10: 衝突形状が宣言できる属性」

use std::fmt;

use super::error::静的物理形状エラー;

#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct 衝突対象の安定識別子 {
    綴り: String,
}

impl 衝突対象の安定識別子 {
    /// 空の綴りと、正準でない綴り(前後に空白が付いたもの)を拒む。落とさずに拒むのは、正準化がここより上流で
    /// 済んでおり、ここで黙って落とすと重複の判定を通った綴りと焼き上がりの綴りが食い違うためである。
    pub fn 生成する(綴り: &str) -> Result<Self, 静的物理形状エラー> {
        if 綴り.is_empty() {
            return Err(静的物理形状エラー::安定識別子が空);
        }
        if 綴り != 綴り.trim() {
            return Err(静的物理形状エラー::安定識別子が前後に空白を持つ);
        }
        Ok(Self { 綴り: 綴り.to_string() })
    }

    pub fn 綴り(&self) -> &str {
        &self.綴り
    }
}

impl fmt::Display for 衝突対象の安定識別子 {
    fn fmt(&self, 出力: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(出力, "{}", self.綴り)
    }
}
