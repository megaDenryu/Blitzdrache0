//! 静的物理形状の値が拒む破れと、数え上げの口が返す組の試験。

use blitz_math::{クォータニオン, メートル, ローカル, 位置};

use super::shape_fixture::{建物1棟の静的物理形状を作る, 直方体を作る};
use super::{
    チャンクの静的物理形状, 任意姿勢の直方体, 子形状識別子, 直方体の軸ごとの半分の長さ, 衝突対象の子形状, 衝突対象の安定識別子, 静的な衝突対象,
    静的物理形状エラー,
};
use crate::asset::チャンクの基準原点からの許容メートル;

fn 恒等の回転() -> クォータニオン<ローカル, ローカル> {
    クォータニオン::恒等()
}

fn 一辺が1の半分の長さ() -> 直方体の軸ごとの半分の長さ {
    match 直方体の軸ごとの半分の長さ::生成する([メートル::生成する(0.5); 3]) {
        Ok(値) => 値,
        Err(誤り) => panic!("半分の長さを作れなかった: {誤り}"),
    }
}

#[test]
fn 半分の長さが負なら拒む() {
    let 結果 = 直方体の軸ごとの半分の長さ::生成する([メートル::生成する(1.0), メートル::生成する(-0.1), メートル::生成する(1.0)]);
    assert_eq!(結果, Err(静的物理形状エラー::半分の長さが負か非有限 { 軸: "Y" }));
}

#[test]
fn 厚みの無い板は受け入れる() {
    assert!(直方体の軸ごとの半分の長さ::生成する([メートル::生成する(1.0), メートル::生成する(0.0), メートル::生成する(1.0)]).is_ok());
}

#[test]
fn 中心がチャンクの基準原点から離れすぎたら拒む() {
    let 中心 = 位置::生成する(
        メートル::生成する(0.0),
        メートル::生成する(0.0),
        メートル::生成する(チャンクの基準原点からの許容メートル + 1.0),
    );
    let 結果 = 任意姿勢の直方体::生成する(中心, 恒等の回転(), 一辺が1の半分の長さ());
    assert_eq!(結果, Err(静的物理形状エラー::中心が範囲外 { 軸: "Z" }));
}

#[test]
fn 子形状を持たない衝突対象は拒む() {
    let Ok(識別子) = 衝突対象の安定識別子::生成する("建物1") else {
        panic!("安定識別子を作れなかった");
    };
    let 結果 = 静的な衝突対象::安定識別子と子形状一覧から生成する(識別子, Vec::new());
    assert_eq!(結果, Err(静的物理形状エラー::子形状が空));
}

#[test]
fn 子形状識別子が重複したら拒む() {
    let Ok(識別子) = 衝突対象の安定識別子::生成する("建物1") else {
        panic!("安定識別子を作れなかった");
    };
    let 子形状 = 衝突対象の子形状::識別子と直方体から生成する(子形状識別子::番号から生成する(3), 直方体を作る(1.0));
    let 結果 = 静的な衝突対象::安定識別子と子形状一覧から生成する(識別子, vec![子形状, 子形状]);
    assert_eq!(結果, Err(静的物理形状エラー::子形状識別子が重複する { 番号: 3 }));
}

#[test]
fn 安定識別子が空なら拒む() {
    assert_eq!(衝突対象の安定識別子::生成する("  "), Err(静的物理形状エラー::安定識別子が空));
}

#[test]
fn チャンクの中で安定識別子が重複したら拒む() {
    let 形状 = 建物1棟の静的物理形状を作る("建物1");
    let 一覧 = vec![形状.衝突対象一覧()[0].clone(), 形状.衝突対象一覧()[0].clone()];
    assert_eq!(
        チャンクの静的物理形状::衝突対象一覧から生成する(一覧),
        Err(静的物理形状エラー::安定識別子が重複する)
    );
}

#[test]
fn 数え上げは親の綴りと子形状の組を据えた順に返す() {
    let 形状 = 建物1棟の静的物理形状を作る("建物1");
    let 組一覧: Vec<(String, u32)> = 形状
        .親を添えて子形状を数え上げる()
        .map(|(親, 子)| (親.綴り().to_string(), 子.識別子().番号を返す()))
        .collect();
    assert_eq!(組一覧, vec![("建物1".to_string(), 0), ("建物1".to_string(), 1)]);
    assert_eq!((形状.衝突対象数(), 形状.子形状の総数()), (1, 2));
}
