//! 読込済みチャンクの形の版: ゲームが読む読込済みチャンクの形の集合(チャンクごとの静的物理形状の保管)が変わるたびに1つ進む
//! 単調増加の番号。保管を変える3つの操作(載せる・外す・空にする)がどれも同じ版を進めるため、保管の外に版を進める経路は無い。
//! 刻みは受け取った版を記録し、1つの描画の全刻みが同じ形を見たことと、描画をまたいで形が変わった回数を、終了時の報告で観測できるようにする。
//! ストリーミングを使わない起動は読込済みチャンクを1つも持たず形が変わらないため、常に最初の版を名乗る(値なしで表さない)。
//! 参照: `_doc/設計/チャンクストリーミング.md`「刻みが見る世界の形の版」

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct 読込済みチャンクの形の版(u64);

impl 読込済みチャンクの形の版 {
    /// 読込済みチャンクの形をまだ1度も変えていない状態の版。ストリーミングを使わない起動は常にこの値である。
    pub const fn 最初を作る() -> Self {
        Self(0)
    }

    /// 形が1回変わった後の版。u64の1回ごとの前進が尽きることは実行時間の範囲で起きないため、尽きたら破られた不変条件として止める。
    pub fn 次を作る(self) -> Self {
        Self(self.0.checked_add(1).unwrap_or_else(|| panic!("読込済みチャンクの形の版がu64を使い切った(1描画に高々数回しか進まない版が2の64乗回進むことは無い)")))
    }

    /// 報告の表示だけが数値へ剥がす。
    pub const fn 番号を返す(self) -> u64 {
        self.0
    }
}
