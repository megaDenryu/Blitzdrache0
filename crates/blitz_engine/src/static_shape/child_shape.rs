//! 衝突対象の子形状: 1つの衝突対象を成す直方体1件と、その対象の中での識別子、およびその直方体を包む軸平行の直方体。
//!
//! 直方体だけの列にしないのは、問い合わせの答えが「どの物体のどの部分に当たったか」を返せなければならないためである。
//! 並びの添字で代用すると、将来この列から物理を持たない部品を落としたときに番号が黙ってずれる。
//!
//! 包む箱を持たせるのは、空間索引の選別が1フレームに何度も走るのに対し、形が読込から解除まで動かないためである。
//! 生成のときに1度だけ合成し、問い合わせのたびには合成しない。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断9: 複合形状は子形状を束ねて1つの衝突対象にする」

use blitz_collision::shape::{任意姿勢の直方体, 軸平行の直方体};
use blitz_math::ローカル;

use super::child_shape_identifier::子形状識別子;

/// 1つの衝突対象を成す直方体1件と、その対象の中での識別子。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 衝突対象の子形状 {
    識別子: 子形状識別子,
    直方体: 任意姿勢の直方体,
    外接する軸平行の直方体: 軸平行の直方体<ローカル>,
}

impl 衝突対象の子形状 {
    /// 識別子と直方体を組にし、包む箱をここで1度だけ合成する。識別子も直方体も既に自分の不変条件を満たしているため、
    /// ここでの検査は要らない。
    pub fn 識別子と直方体から生成する(識別子: 子形状識別子, 直方体: 任意姿勢の直方体) -> Self {
        Self {
            識別子,
            直方体,
            外接する軸平行の直方体: 直方体.外接する軸平行の直方体を求める(),
        }
    }

    /// この子形状が属する衝突対象の中での識別子。
    pub fn 識別子(&self) -> 子形状識別子 {
        self.識別子
    }

    /// この子形状の形そのものである、群のローカル空間の直方体。
    pub fn 直方体(&self) -> 任意姿勢の直方体 {
        self.直方体
    }

    /// この子形状の形を包む、群のローカル空間で軸平行の直方体。空間索引の2段目の選別がこれを見る。
    pub fn 外接する軸平行の直方体(&self) -> 軸平行の直方体<ローカル> {
        self.外接する軸平行の直方体
    }
}
