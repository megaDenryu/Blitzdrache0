//! チャンクごとの静的物理形状の保管の出入りの試験。

use super::shape_fixture::建物1棟の静的物理形状を作る;
use super::{チャンクごとの静的物理形状の保管, チャンクの静的物理形状};
use crate::チャンク座標;

#[test]
fn 載せた座標だけを引ける() {
    let mut 保管 = チャンクごとの静的物理形状の保管::空を作る();
    保管.載せる(チャンク座標::生成する(1, 2), 建物1棟の静的物理形状を作る("建物1"));
    assert_eq!(保管.登録数(), 1);
    assert_eq!(
        保管.座標で引く(チャンク座標::生成する(1, 2)).map(チャンクの静的物理形状::子形状の総数),
        Some(2)
    );
    assert!(保管.座標で引く(チャンク座標::生成する(0, 0)).is_none());
}

#[test]
fn 外すと引けなくなる() {
    let mut 保管 = チャンクごとの静的物理形状の保管::空を作る();
    保管.載せる(チャンク座標::生成する(1, 2), 建物1棟の静的物理形状を作る("建物1"));
    保管.外す(チャンク座標::生成する(1, 2));
    assert_eq!(保管.登録数(), 0);
    保管.外す(チャンク座標::生成する(1, 2));
    assert_eq!(保管.登録数(), 0);
}

#[test]
fn 同じ座標へ載せ直すと後から載せたものになる() {
    let mut 保管 = チャンクごとの静的物理形状の保管::空を作る();
    保管.載せる(チャンク座標::生成する(0, 0), 建物1棟の静的物理形状を作る("建物1"));
    保管.載せる(チャンク座標::生成する(0, 0), 建物1棟の静的物理形状を作る("建物2"));
    let Some(形状) = 保管.座標で引く(チャンク座標::生成する(0, 0)) else {
        panic!("載せ直した形状を引けなかった");
    };
    assert_eq!(形状.衝突対象一覧()[0].安定識別子().綴り(), "建物2");
    assert_eq!(保管.登録数(), 1);
}

#[test]
fn 空にすると全部消える() {
    let mut 保管 = チャンクごとの静的物理形状の保管::空を作る();
    保管.載せる(チャンク座標::生成する(0, 0), 建物1棟の静的物理形状を作る("建物1"));
    保管.載せる(チャンク座標::生成する(1, 0), 建物1棟の静的物理形状を作る("建物2"));
    保管.空にする();
    assert_eq!(保管.登録数(), 0);
}
