//! チャンクごとの静的物理形状の保管の出入りと、出入りに伴う読込済みチャンクの形の版の前進の試験。

use super::shape_fixture::建物1棟の静的物理形状を作る;
use super::{チャンクごとの静的物理形状の保管, チャンクの静的物理形状, 読込済みチャンクの形の版};
use crate::チャンク座標;

#[test]
fn 載せた座標だけを参照できる() {
    let mut 保管 = チャンクごとの静的物理形状の保管::空を作る();
    保管.載せる(チャンク座標::生成する(1, 2), 建物1棟の静的物理形状を作る("建物1"));
    assert_eq!(保管.登録数(), 1);
    assert_eq!(保管.座標で参照する(チャンク座標::生成する(1, 2)).map(チャンクの静的物理形状::子形状の総数), Some(2));
    assert!(保管.座標で参照する(チャンク座標::生成する(0, 0)).is_none());
}

#[test]
fn 外すと参照できなくなる() {
    let mut 保管 = チャンクごとの静的物理形状の保管::空を作る();
    保管.載せる(チャンク座標::生成する(1, 2), 建物1棟の静的物理形状を作る("建物1"));
    保管.外す(チャンク座標::生成する(1, 2));
    assert_eq!(保管.登録数(), 0);
    保管.外す(チャンク座標::生成する(1, 2));
    assert_eq!(保管.登録数(), 0);
}

#[test]
fn 同じ座標へ載せ直すと後から載せたものになる() {
    let mut 保管 = チャンクごとの静的物理形状の保管::空を作る();
    保管.載せる(チャンク座標::生成する(0, 0), 建物1棟の静的物理形状を作る("建物1"));
    保管.載せる(チャンク座標::生成する(0, 0), 建物1棟の静的物理形状を作る("建物2"));
    let Some(形状) = 保管.座標で参照する(チャンク座標::生成する(0, 0)) else {
        panic!("載せ直した形状を参照できなかった");
    };
    assert_eq!(形状.衝突対象一覧()[0].安定識別子().綴り(), "建物2");
    assert_eq!(保管.登録数(), 1);
}

#[test]
fn 空にすると全部消える() {
    let mut 保管 = チャンクごとの静的物理形状の保管::空を作る();
    保管.載せる(チャンク座標::生成する(0, 0), 建物1棟の静的物理形状を作る("建物1"));
    保管.載せる(チャンク座標::生成する(1, 0), 建物1棟の静的物理形状を作る("建物2"));
    保管.空にする();
    assert_eq!(保管.登録数(), 0);
}

/// 反証: 中身を変える操作のどれかが版を進めないと、その経路で形が変わった描画を刻みが観測できなくなる。
#[test]
fn 中身を変える3つの操作がどれも版を進める() {
    let mut 保管 = チャンクごとの静的物理形状の保管::空を作る();
    assert_eq!(保管.版(), 読込済みチャンクの形の版::最初を作る());
    保管.載せる(チャンク座標::生成する(0, 0), 建物1棟の静的物理形状を作る("建物1"));
    let 載せた後 = 読込済みチャンクの形の版::最初を作る().次を作る();
    assert_eq!(保管.版(), 載せた後);
    保管.外す(チャンク座標::生成する(0, 0));
    assert_eq!(保管.版(), 載せた後.次を作る());
    保管.空にする();
    assert_eq!(保管.版(), 載せた後.次を作る().次を作る());
}

/// 載っていない座標を外す報告と、既に空の保管を空にする指示は、どちらも届きうる。どちらでも版は進む。
/// 版が守るのは「中身が変わったのに進まないことが無い」ことであり、進みすぎは刻みの観測として安全側である。
#[test]
fn 中身が動かない外すと空にするでも版は進む() {
    let mut 保管 = チャンクごとの静的物理形状の保管::空を作る();
    保管.外す(チャンク座標::生成する(3, 4));
    assert_eq!(保管.登録数(), 0);
    assert_eq!(保管.版(), 読込済みチャンクの形の版::最初を作る().次を作る());
    保管.空にする();
    assert_eq!(保管.版(), 読込済みチャンクの形の版::最初を作る().次を作る().次を作る());
}
