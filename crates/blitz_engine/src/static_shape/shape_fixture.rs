//! 試験が使う静的物理形状の材料。実行時形式の往復と保管の出入りの両方が同じ形を使うことで、
//! 片方だけを直したときに食い違いが出ないようにする。
//!
//! 回転に天頂まわりの半回転を使うのは、恒等でないうえに4成分が倍精度でも単精度でも厳密に表せる値であり、
//! 正規化を通しても1ビットも動かないためである。動く値を使うと、往復の一致が浮動小数点の丸めに左右される。

use blitz_math::{クォータニオン, メートル, ローカル, 位置};

use super::{
    チャンクの静的物理形状, 任意姿勢の直方体, 子形状識別子, 直方体の軸ごとの半分の長さ, 衝突対象の子形状, 衝突対象の安定識別子, 静的な衝突対象,
};

pub(crate) fn 直方体を作る(中心の東: f32) -> 任意姿勢の直方体 {
    let Ok(回転) = クォータニオン::<ローカル, ローカル>::生成する(0.0, 1.0, 0.0, 0.0) else {
        panic!("試験用の回転を作れなかった");
    };
    let Ok(半分の長さ) =
        直方体の軸ごとの半分の長さ::生成する([メートル::生成する(1.5), メートル::生成する(1.25), メートル::生成する(0.25)])
    else {
        panic!("試験用の半分の長さを作れなかった");
    };
    let 中心 = 位置::生成する(メートル::生成する(中心の東), メートル::生成する(2.5), メートル::生成する(-3.5));
    match 任意姿勢の直方体::生成する(中心, 回転, 半分の長さ) {
        Ok(直方体) => 直方体,
        Err(誤り) => panic!("試験用の直方体を作れなかった: {誤り}"),
    }
}

/// 子形状を2件持つ衝突対象1件。
pub(crate) fn 衝突対象を作る(綴り: &str) -> 静的な衝突対象 {
    let Ok(安定識別子) = 衝突対象の安定識別子::生成する(綴り) else {
        panic!("試験用の安定識別子を作れなかった");
    };
    let 子形状一覧 = vec![
        衝突対象の子形状::識別子と直方体から生成する(子形状識別子::番号から生成する(0), 直方体を作る(1.0)),
        衝突対象の子形状::識別子と直方体から生成する(子形状識別子::番号から生成する(1), 直方体を作る(4.0)),
    ];
    match 静的な衝突対象::安定識別子と子形状一覧から生成する(安定識別子, 子形状一覧) {
        Ok(対象) => 対象,
        Err(誤り) => panic!("試験用の衝突対象を作れなかった: {誤り}"),
    }
}

pub(crate) fn 綴り一覧から形状を作る(綴り一覧: &[&str]) -> チャンクの静的物理形状 {
    let 一覧 = 綴り一覧.iter().map(|綴り| 衝突対象を作る(綴り)).collect();
    match チャンクの静的物理形状::衝突対象一覧から生成する(一覧) {
        Ok(形状) => 形状,
        Err(誤り) => panic!("試験用のチャンクの形状を作れなかった: {誤り}"),
    }
}

pub(crate) fn 建物1棟の形状を作る(綴り: &str) -> チャンクの静的物理形状 {
    綴り一覧から形状を作る(&[綴り])
}
