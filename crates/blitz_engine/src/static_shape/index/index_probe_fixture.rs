//! 空間索引の試験が問い合わせを出す材料と、返った候補を人が読める形へ落とす読み取り。
//!
//! 調べられる世界を組む材料は`index_fixture.rs`が持つ。ここが持つのは、その世界へ何をどこから尋ねるかと、
//! 答えのどこを見るかである。

use blitz_math::{メートル, ワールド, 変位, 大域メートル, 大域ワールド位置, 方向};

use super::super::storage::チャンクごとの静的物理形状の保管;
use super::candidate::静的な子形状の候補;
use super::index_fixture::試験のチャンクの一辺;
use super::query::静的世界の候補の選別;

pub(super) fn 大域の位置(成分: [f64; 3]) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(成分[0]),
        大域メートル::生成する(成分[1]),
        大域メートル::生成する(成分[2]),
    )
}

/// 東へ指定のメートル数だけ進む変位。掃引の試験が覆いを東へ伸ばすのに使う。
pub(super) fn 東へ進む変位(メートル数: f32) -> 変位<ワールド> {
    let 東 = match 方向::<ワールド>::生成する(1.0, 0.0, 0.0) {
        Ok(方向) => 方向,
        Err(誤り) => panic!("試験用の方向を作れなかった: {誤り}"),
    };
    変位::方向へ進む(東, メートル::生成する(メートル数))
}

pub(super) fn 選別を作る(保管: &チャンクごとの静的物理形状の保管) -> 静的世界の候補の選別<'_> {
    match 静的世界の候補の選別::保管とチャンクの一辺から生成する(保管, 試験のチャンクの一辺()) {
        Ok(選別) => 選別,
        Err(誤り) => panic!("試験用の選別を作れなかった: {誤り}"),
    }
}

// 候補を人が読める組へ落とす。チャンクの座標・親の綴り・子形状の番号の3つが答えの実体である。
pub(super) fn 候補を組へ落とす(候補一覧: &[静的な子形状の候補<'_>]) -> Vec<(i32, i32, String, u32)> {
    候補一覧.iter().map(候補1件を組へ落とす).collect()
}

fn 候補1件を組へ落とす(候補: &静的な子形状の候補<'_>) -> (i32, i32, String, u32) {
    (
        候補.チャンク座標().x(),
        候補.チャンク座標().z(),
        候補.衝突対象の安定識別子().綴り().to_string(),
        候補.子形状識別子().番号を返す(),
    )
}
