//! 覆いが跨ぐチャンク座標の矩形: 問い合わせの覆いが触れる区域が、どのチャンク座標の矩形に収まるかを表す型。
//!
//! この矩形は候補の列挙には使わない。子形状を包む箱が所有チャンクの区画へ収まる保証が無いためである。子形状の中心は
//! チャンクの基準原点から許容の範囲にあるが、軸ごとの半分の長さは形状の座標の上限まで取れるため、箱は隣のチャンクへ
//! 張り出しうる。矩形の中の座標だけを見ると、その張り出した形を落とす。列挙は読込済みチャンクの全走査が行う
//! (`query_gather.rs`)。
//!
//! ここが答えるのは完全性だけである。覆いが触れる区域の全体を評価できたかは「矩形の中のチャンクが1つ残らず読み
//! 込まれているか」で決まり、その判定に矩形の座標を数え上げる必要は無い。読込済みチャンクのうち矩形に入るものを数え、
//! 矩形のチャンク件数と比べれば足りる。数え上げないため、費用は覆いの広さに依らず、覆いの広さへ上限を課す理由も無い。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断8: 問い合わせの値と完全性を別軸にする」
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断12: 空間探索は粗い候補選別と詳細判定を責務として分け、世界は二段構えで辿る」

use blitz_collision::shape::大域の軸平行の直方体;

use super::error::静的世界の候補の選別エラー;
use crate::{チャンク座標, チャンク格子};

pub(super) struct 覆いが跨ぐチャンク座標の矩形 {
    東の始まり: i32,
    東の終わり: i32,
    南の始まり: i32,
    南の終わり: i32,
}

impl 覆いが跨ぐチャンク座標の矩形 {
    // 覆いの2つの端が属するチャンクの座標を格子へ尋ね、その間の矩形にする。端の位置を格子の座標へ写せない覆いは
    // 型付きエラーで拒む。
    pub(super) fn 覆いと格子から求める(
        覆い: &大域の軸平行の直方体,
        格子: チャンク格子,
    ) -> Result<Self, 静的世界の候補の選別エラー> {
        let 最小の座標 = 格子.所属座標を求める(覆い.最小の端())?;
        let 最大の座標 = 格子.所属座標を求める(覆い.最大の端())?;
        Ok(Self {
            東の始まり: 最小の座標.x(),
            東の終わり: 最大の座標.x(),
            南の始まり: 最小の座標.z(),
            南の終わり: 最大の座標.z(),
        })
    }

    pub(super) fn 座標を含むか(&self, 座標: チャンク座標) -> bool {
        (self.東の始まり..=self.東の終わり).contains(&座標.x()) && (self.南の始まり..=self.南の終わり).contains(&座標.z())
    }

    // 128ビットで積を取るのは、両軸が32ビットいっぱいに広がると件数の積が64ビットをちょうど1だけ越えるためである。
    pub(super) fn チャンク件数(&self) -> u128 {
        let 東の件数 = u64::from(self.東の終わり.abs_diff(self.東の始まり)) + 1;
        let 南の件数 = u64::from(self.南の終わり.abs_diff(self.南の始まり)) + 1;
        u128::from(東の件数) * u128::from(南の件数)
    }
}
