//! 覆いが跨ぐチャンク座標の並び: 問い合わせの覆いが触れうるチャンクの座標を、順序を固定して数え上げる型。
//!
//! 上位の粗い選別をチャンクにするのは、静的な形の寿命がチャンクの読込と解除で決まり、答えられる範囲がその単位で
//! 切れるためである。世界全体を1つの木へ固定しない理由は判断12にある。
//!
//! 並びの順序を`チャンク座標`自身の順序(東を先、南を後に見る辞書式)の昇順に合わせるのは、同じ入力から常に同じ順の
//! 候補が出るようにするためである。順序が入力だけで決まらないと、候補を先着で1件選ぶ利用側の答えが実行ごとに変わる。
//!
//! 件数に上限を置くのは、覆いが世界の端から端まで伸びると平坦な走査がチャンクの数だけ伸びるためである。上限を越える
//! 覆いは近傍の問い合わせではなく、平坦な選別が道具として合っていない。黙って走り続けるより型付きエラーで止める。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断12: 空間探索は粗い候補選別と詳細判定を責務として分け、世界は二段構えで辿る」

use blitz_collision::shape::大域の軸平行の直方体;

use super::error::静的世界の候補の選別エラー;
use crate::{チャンク座標, チャンク格子};

/// 1回の問い合わせの覆いが跨げるチャンクの上限件数。1辺32チャンクの正方形にあたる。
pub const 覆いが跨げるチャンクの上限件数: i64 = 1024;

pub(super) struct 覆いが跨ぐチャンク座標の並び {
    東の始まり: i32,
    東の終わり: i32,
    南の始まり: i32,
    南の終わり: i32,
}

impl 覆いが跨ぐチャンク座標の並び {
    // 覆いの2つの端が属するチャンクの座標を格子へ尋ね、その間の矩形を並びにする。端の位置を格子の座標へ写せない
    // 覆いと、上限を越える広がりの覆いは型付きエラーで拒む。
    pub(super) fn 覆いと格子から求める(
        覆い: &大域の軸平行の直方体,
        格子: チャンク格子,
    ) -> Result<Self, 静的世界の候補の選別エラー> {
        let 最小の座標 = 格子.所属座標を求める(覆い.最小の端())?;
        let 最大の座標 = 格子.所属座標を求める(覆い.最大の端())?;
        let 並び = Self {
            東の始まり: 最小の座標.x(),
            東の終わり: 最大の座標.x(),
            南の始まり: 最小の座標.z(),
            南の終わり: 最大の座標.z(),
        };
        並び.件数が上限に収まることを確かめる()?;
        Ok(並び)
    }

    // 東を外側・南を内側の昇順で並べる。`チャンク座標`の順序と同じ向きである。
    pub(super) fn 座標を並べる(self) -> impl Iterator<Item = チャンク座標> {
        let 南の範囲 = self.南の始まり..=self.南の終わり;
        (self.東の始まり..=self.東の終わり).flat_map(move |東| 南の範囲.clone().map(move |南| チャンク座標::生成する(東, 南)))
    }

    // 軸ごとに数えてから積を取る。先に軸ごとを見るのは、両軸が32ビットいっぱいに広がると積が64ビットで桁あふれするためである。
    fn 件数が上限に収まることを確かめる(&self) -> Result<(), 静的世界の候補の選別エラー> {
        let 東の件数 = i64::from(self.東の終わり) - i64::from(self.東の始まり) + 1;
        let 南の件数 = i64::from(self.南の終わり) - i64::from(self.南の始まり) + 1;
        for 軸ごとの件数 in [東の件数, 南の件数] {
            if 軸ごとの件数 > 覆いが跨げるチャンクの上限件数 {
                return Err(静的世界の候補の選別エラー::覆いが跨ぐチャンクが多すぎる { 件数: 軸ごとの件数 });
            }
        }
        let 件数 = 東の件数 * 南の件数;
        if 件数 > 覆いが跨げるチャンクの上限件数 {
            return Err(静的世界の候補の選別エラー::覆いが跨ぐチャンクが多すぎる { 件数 });
        }
        Ok(())
    }
}
