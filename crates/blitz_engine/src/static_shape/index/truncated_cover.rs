//! 当たりの時刻までへ切り詰めた覆いの完全性を答える工程。受け取るのは問い合わせの入力と当たりの時刻(掃引なら
//! 動けた割合)、返すのはその範囲だけを覆う箱についての完全性である。候補は1件も挙げない。
//!
//! 切り詰めが要るのは、覆いの完全性が覆い全体の集計であり、読み込まれていないチャンクが当たりより手前に在るのか
//! 奥に在るのかを持たないためである。掃引の覆いは動き切った先まで伸びるため、当たりの後ろだけが未読込でも完全性が
//! 落ちる。当たりより手前へ切り詰めた覆いが完全なら、その当たりより早い当たりは在りえず、答えは確定する。
//!
//! 候補を挙げ直さないのは、覆い全体で挙げた候補が切り詰めた覆いの候補をすべて含むためである。切り詰めた覆いは
//! 覆い全体に収まるから、切り詰めた覆いに触れる形は覆い全体にも触れており、既に挙がっている。
//!
//! いつ呼ばれるか。当たりが見つかったのに覆いの完全性が落ちた問い合わせだけが呼ぶ。費用は読込済みチャンクの件数に
//! 比例する数え上げ1回であり、子形状を包む箱の比較を1つも行わない。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断8: 問い合わせの値と完全性を別軸にする」

use blitz_collision::shape::大域の軸平行の直方体;
use blitz_math::{メートル, ワールド, 変位, 大域ワールド位置};

use super::chunk_span::覆いが跨ぐチャンク座標の矩形;
use super::error::静的世界の候補の選別エラー;
use super::query::{
    位置が有限であることを確かめる, 掃引の入力が覆いを組める値であることを確かめる, 静的世界の候補の選別
};
use crate::world_query::問い合わせ完全性;

impl<'形状> 静的世界の候補の選別<'形状> {
    /// 線分を当たりの時刻までへ切り詰めた覆いについて、完全性だけを問い直す。時刻は線分の全体を1としたときの値である。
    pub fn 線分を当たりの時刻まで切り詰めた覆いの完全性を求める(
        &self,
        始点: 大域ワールド位置,
        終点: 大域ワールド位置,
        当たりの時刻: f64,
    ) -> Result<問い合わせ完全性, 静的世界の候補の選別エラー> {
        位置が有限であることを確かめる(始点)?;
        位置が有限であることを確かめる(終点)?;
        self.覆いの完全性を求める(
            &大域の軸平行の直方体::端から比のぶんだけ進んだところまでに外接する箱を求める(
                始点,
                終点,
                当たりの時刻,
            ),
        )
    }

    /// 掃引を接触の割合までへ切り詰めた覆いについて、完全性だけを問い直す。割合は変位の全体を1としたときの値である。
    pub fn 掃引を接触の割合まで切り詰めた覆いの完全性を求める(
        &self,
        軸の始点: 大域ワールド位置,
        軸の終点: 大域ワールド位置,
        半径: メートル,
        掃引の変位: 変位<ワールド>,
        接触の割合: f64,
    ) -> Result<問い合わせ完全性, 静的世界の候補の選別エラー> {
        掃引の入力が覆いを組める値であることを確かめる(軸の始点, 軸の終点, 半径, 掃引の変位)?;
        let 覆い = 大域の軸平行の直方体::二点に外接する箱を求める(軸の始点, 軸の終点)
            .全方向へ広げた箱を求める(半径)
            .変位の先頭の比のぶんだけ掃いた箱を求める(掃引の変位, 接触の割合);
        self.覆いの完全性を求める(&覆い)
    }

    fn 覆いの完全性を求める(
        &self,
        覆い: &大域の軸平行の直方体,
    ) -> Result<問い合わせ完全性, 静的世界の候補の選別エラー> {
        let 矩形 = 覆いが跨ぐチャンク座標の矩形::覆いと格子から求める(覆い, self.格子())?;
        Ok(矩形.読込済みチャンクで埋まるかを求める(self.保管()))
    }
}
