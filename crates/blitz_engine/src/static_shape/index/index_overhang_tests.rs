// 張り出していない形まで挙げてしまうと、この選別は候補を絞る道具でなくなる。隣のチャンクの遠くの建物が挙がらない
// ことを、上の2件と同じ形の世界で見る。
#[test]
fn 隣のチャンクの遠くの形は候補に挙がらない() {
    let 保管 = 保管を組む(vec![
        (チャンク座標::生成する(0, 0), vec![衝突対象を作る("遠くの建物", &[[10.0, 0.0, 0.0]])]),
        (チャンク座標::生成する(1, 0), Vec::new()),
    ]);
    let 選別 = 選別を作る(&保管);
    let mut 受け皿 = Vec::new();
    let Ok(_) = 選別.線分に触れうる子形状の候補を集める(大域の位置([64.0, 0.0, 0.0]), 大域の位置([80.0, 0.0, 0.0]), &mut 受け皿)
    else {
        panic!("候補を集められなかった");
    };
    assert!(受け皿.is_empty(), "覆いから離れた形が候補に挙がっている");
}
