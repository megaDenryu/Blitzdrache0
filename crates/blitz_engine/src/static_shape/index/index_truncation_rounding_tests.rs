//! 覆いを当たりのところまで切り詰める計算の丸めが、完全性を偽らないことの反証。
//!
//! 切り詰めた端は減算と積と和の丸めを通るため、真の端がチャンクの境界をちょうど踏むところで計算値が内側へ落ちる。
//! その端をそのまま矩形へ写すと未読込の隣のチャンクが覆いから外れ、読込済みのチャンクだけで矩形が埋まって
//! 「対象範囲を完全に評価できた」と答える。その答えは当たりを確定として返してよいという判断へ渡るため、確定でない
//! 当たりが確定になる。
//!
//! 読み込むのは東の座標がマイナス1と0の2チャンクであり、東の座標1のチャンクは読み込まない。線分と掃引のどちらも、
//! 真の切り詰めた端が東64メートル(東の座標1の始まり)に達し、倍精度で組んだ端はその1刻み内側へ落ちる値を選んである。
//! 端を外向きへ広げていなければ、矩形は東の座標0までで閉じて完全と答える。
//! 参照: `crates/blitz_collision/src/shape/truncation_rounding_margin.rs`

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::super::storage::チャンクごとの静的物理形状の保管;
use super::index_fixture::{保管を組む, 衝突対象を作る};
use super::index_probe_fixture::{大域の位置, 東へ進む変位, 選別を作る};
use crate::world_query::問い合わせ完全性;
use crate::チャンク座標;

// 東の座標がマイナス1と0の2チャンクだけを読み込んだ世界。東の座標1は読み込まない。
fn 東の座標0までを読み込んだ保管() -> チャンクごとの静的物理形状の保管 {
    保管を組む(vec![
        (チャンク座標::生成する(-1, 0), vec![衝突対象を作る("西の建物", &[[10.0, 0.0, 10.0]])]),
        (チャンク座標::生成する(0, 0), vec![衝突対象を作る("東の建物", &[[10.0, 0.0, 10.0]])]),
    ])
}

#[test]
fn 線分の切り詰めた端が丸めで内側へ落ちても未読込の隣チャンクを矩形から外さない() {
    let (始点の東, 終点の東, 当たりの時刻) = (-19.6_f64, 64.5_f64, 0.9940546967895363_f64);
    assert!(始点の東 + (終点の東 - 始点の東) * 当たりの時刻 < 64.0); // 真の端は東64メートルを越える
    let 保管 = 東の座標0までを読み込んだ保管();
    let 完全性 = 選別を作る(&保管)
        .線分を当たりの時刻まで切り詰めた覆いの完全性を求める(
            大域の位置([始点の東, 0.0, 1.0]),
            大域の位置([終点の東, 0.0, 1.0]),
            当たりの時刻,
        )
        .unwrap();
    assert_eq!(完全性, 問い合わせ完全性::評価できない領域を含む);
}

#[test]
fn 線分の切り詰めた端がチャンクの境界から離れていれば完全と答える() {
    let 保管 = 東の座標0までを読み込んだ保管();
    let 完全性 = 選別を作る(&保管)
        .線分を当たりの時刻まで切り詰めた覆いの完全性を求める(
            大域の位置([-19.6, 0.0, 1.0]),
            大域の位置([64.5, 0.0, 1.0]),
            0.5,
        )
        .unwrap();
    assert_eq!(完全性, 問い合わせ完全性::対象範囲を完全に評価できた);
}

#[test]
fn 掃引の切り詰めた端が丸めで内側へ落ちても未読込の隣チャンクを矩形から外さない() {
    let (軸の東, 半径メートル, 掃引の東メートル, 接触の割合) = (-18.1_f64, 0.5_f32, 160.0_f32, 0.51_f64);
    assert!(軸の東 + f64::from(半径メートル) + f64::from(掃引の東メートル) * 接触の割合 < 64.0); // 真の端は東64メートル
    let 保管 = 東の座標0までを読み込んだ保管();
    let 完全性 = 選別を作る(&保管)
        .掃引を接触の割合まで切り詰めた覆いの完全性を求める(
            大域の位置([軸の東, 4.0, 1.0]),
            大域の位置([軸の東, 6.0, 1.0]),
            メートル::生成する(半径メートル),
            東へ進む変位(掃引の東メートル),
            接触の割合,
        )
        .unwrap();
    assert_eq!(完全性, 問い合わせ完全性::評価できない領域を含む);
}

#[test]
fn 掃引の切り詰めた端がチャンクの境界から離れていれば完全と答える() {
    let 保管 = 東の座標0までを読み込んだ保管();
    let 完全性 = 選別を作る(&保管)
        .掃引を接触の割合まで切り詰めた覆いの完全性を求める(
            大域の位置([-18.1, 4.0, 1.0]),
            大域の位置([-18.1, 6.0, 1.0]),
            メートル::生成する(0.5),
            東へ進む変位(160.0),
            0.25,
        )
        .unwrap();
    assert_eq!(完全性, 問い合わせ完全性::対象範囲を完全に評価できた);
}
