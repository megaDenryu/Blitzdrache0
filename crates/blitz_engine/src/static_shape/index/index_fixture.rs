//! 空間索引の試験が調べられる世界を組む材料。チャンクの一辺・形の大きさ・形の置き場を1箇所で決めることで、
//! 試験ごとに違う縮尺の世界を組んで答えが食い違うことを防ぐ。
//!
//! 問い合わせを出す材料と答えの読み取りは`index_probe_fixture.rs`が持つ。世界を組むことと問い合わせを出すことは、
//! 同じ試験でも変える理由が別であるためである。

use blitz_collision::shape::{任意姿勢の直方体, 直方体の軸ごとの半分の長さ};
use blitz_math::{クォータニオン, メートル, ローカル, 位置};

use super::super::child_shape::衝突対象の子形状;
use super::super::child_shape_identifier::子形状識別子;
use super::super::chunk_shapes::チャンクの静的物理形状;
use super::super::collision_object::静的な衝突対象;
use super::super::object_identifier::衝突対象の安定識別子;
use super::super::storage::チャンクごとの静的物理形状の保管;
use crate::{チャンク一辺, チャンク座標};

/// 試験の世界のチャンクの一辺。1辺64メートルは実際の地形と同じ桁であり、群のローカル座標が許容範囲に収まる。
pub(super) const 試験のチャンクの一辺メートル: f32 = 64.0;

pub(super) fn 試験のチャンクの一辺() -> チャンク一辺 {
    match チャンク一辺::生成する(試験のチャンクの一辺メートル) {
        Ok(一辺) => 一辺,
        Err(誤り) => panic!("試験用のチャンクの一辺を作れなかった: {誤り}"),
    }
}

/// 群のローカル空間の指定した中心に置いた、一辺2メートルの軸平行な立方体を1件だけ持つ子形状。
pub(super) fn 立方体の子形状を作る(番号: u32, 中心: [f32; 3]) -> 衝突対象の子形状 {
    let 位置 = 位置::生成する(メートル::生成する(中心[0]), メートル::生成する(中心[1]), メートル::生成する(中心[2]));
    let 半分の長さ = match 直方体の軸ごとの半分の長さ::生成する([メートル::生成する(1.0); 3]) {
        Ok(値) => 値,
        Err(誤り) => panic!("試験用の半分の長さを作れなかった: {誤り}"),
    };
    let 直方体 = match 任意姿勢の直方体::生成する(位置, クォータニオン::<ローカル, ローカル>::恒等(), 半分の長さ)
    {
        Ok(直方体) => 直方体,
        Err(誤り) => panic!("試験用の直方体を作れなかった: {誤り}"),
    };
    衝突対象の子形状::識別子と直方体から生成する(子形状識別子::番号から生成する(番号), 直方体)
}

/// 綴りと、子形状を据える群のローカル空間の中心の並びから、静的な衝突対象を1件作る。
pub(super) fn 衝突対象を作る(綴り: &str, 中心一覧: &[[f32; 3]]) -> 静的な衝突対象 {
    let Ok(安定識別子) = 衝突対象の安定識別子::生成する(綴り) else {
        panic!("試験用の安定識別子を作れなかった");
    };
    let mut 子形状一覧 = Vec::with_capacity(中心一覧.len());
    for (添字, 中心) in 中心一覧.iter().enumerate() {
        let Ok(番号) = u32::try_from(添字) else {
            panic!("試験用の子形状の番号が32ビットに収まらなかった");
        };
        子形状一覧.push(立方体の子形状を作る(番号, *中心));
    }
    match 静的な衝突対象::安定識別子と子形状一覧から生成する(安定識別子, 子形状一覧) {
        Ok(対象) => 対象,
        Err(誤り) => panic!("試験用の衝突対象を作れなかった: {誤り}"),
    }
}

pub(super) fn チャンクの形状を作る(衝突対象一覧: Vec<静的な衝突対象>) -> チャンクの静的物理形状 {
    match チャンクの静的物理形状::衝突対象一覧から生成する(衝突対象一覧) {
        Ok(形状) => 形状,
        Err(誤り) => panic!("試験用のチャンクの形状を作れなかった: {誤り}"),
    }
}

/// 座標と衝突対象の組から保管を組む。載せる順は与えた順であり、選別の並びはこの順に依らない。
pub(super) fn 保管を組む(組一覧: Vec<(チャンク座標, Vec<静的な衝突対象>)>) -> チャンクごとの静的物理形状の保管 {
    let mut 保管 = チャンクごとの静的物理形状の保管::空を作る();
    for (座標, 衝突対象一覧) in 組一覧 {
        保管.載せる(座標, チャンクの形状を作る(衝突対象一覧));
    }
    保管
}

/// 東に2棟だけを置いた1チャンクの世界。1棟目は東10メートル、2棟目は東40メートルにある。
pub(super) fn 東西に2棟を置いた保管() -> チャンクごとの静的物理形状の保管 {
    保管を組む(vec![(
        チャンク座標::生成する(0, 0),
        vec![
            衝突対象を作る("東の建物", &[[10.0, 0.0, 0.0]]),
            衝突対象を作る("西の建物", &[[40.0, 0.0, 0.0]]),
        ],
    )])
}
