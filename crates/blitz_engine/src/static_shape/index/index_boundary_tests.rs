//! 選別の縁の反証。読み込まれていないチャンクを覆いが含むときの完全性、掃引の覆いが半径と変位のぶん広がること、
//! 覆いが広すぎるときと入力が有限でないときに黙って走らず型付きエラーで止まることを見る。

use blitz_math::{メートル, ワールド, 変位, 方向};

use super::index_fixture::{
    保管を組む, 候補を組へ落とす, 大域の位置, 東西に2棟を置いた保管, 衝突対象を作る, 選別を作る
};
use super::静的世界の候補の選別エラー;
use crate::world_query::問い合わせ完全性;
use crate::チャンク座標;

fn 東へ進む変位(メートル数: f32) -> 変位<ワールド> {
    let 東 = match 方向::<ワールド>::生成する(1.0, 0.0, 0.0) {
        Ok(方向) => 方向,
        Err(誤り) => panic!("試験用の方向を作れなかった: {誤り}"),
    };
    変位::方向へ進む(東, メートル::生成する(メートル数))
}

#[test]
fn 読み込まれていないチャンクを覆いが含むと完全性が落ちる() {
    let 保管 = 保管を組む(vec![(
        チャンク座標::生成する(0, 0),
        vec![衝突対象を作る("手前の建物", &[[60.0, 0.0, 0.0]])],
    )]);
    let 選別 = 選別を作る(&保管);
    let mut 受け皿 = Vec::new();
    let 完全性 =
        match 選別.線分に触れうる子形状の候補を集める(大域の位置([58.0, 0.0, 0.0]), 大域の位置([70.0, 0.0, 0.0]), &mut 受け皿)
        {
            Ok(完全性) => 完全性,
            Err(誤り) => panic!("候補を集められなかった: {誤り}"),
        };
    assert_eq!(完全性, 問い合わせ完全性::評価できない領域を含む);
    assert_eq!(候補を組へ落とす(&受け皿), vec![(0, 0, "手前の建物".to_string(), 0)]);
}

#[test]
fn 掃引の覆いは半径と変位のぶん広がる() {
    let 保管 = 保管を組む(vec![(
        チャンク座標::生成する(0, 0),
        vec![
            衝突対象を作る("足元の建物", &[[10.0, 0.0, 0.0]]),
            衝突対象を作る("行き先の建物", &[[16.0, 0.0, 0.0]]),
        ],
    )]);
    let 選別 = 選別を作る(&保管);
    let mut 受け皿 = Vec::new();
    let 軸の始点 = 大域の位置([10.0, 0.0, 0.0]);
    let 軸の終点 = 大域の位置([10.0, 2.0, 0.0]);
    let Ok(_) = 選別.線分に触れうる子形状の候補を集める(軸の始点, 軸の終点, &mut 受け皿) else {
        panic!("線分の列挙に失敗した");
    };
    assert_eq!(候補を組へ落とす(&受け皿), vec![(0, 0, "足元の建物".to_string(), 0)]);
    let Ok(_) = 選別.掃引したカプセルに触れうる子形状の候補を集める(
        軸の始点,
        軸の終点,
        メートル::生成する(0.5),
        東へ進む変位(5.0),
        &mut 受け皿,
    ) else {
        panic!("掃引の列挙に失敗した");
    };
    assert_eq!(
        候補を組へ落とす(&受け皿),
        vec![(0, 0, "足元の建物".to_string(), 0), (0, 0, "行き先の建物".to_string(), 0)]
    );
}

#[test]
fn 覆いが広すぎるチャンクの数を跨ぐと型付きエラーで止まる() {
    let 保管 = 東西に2棟を置いた保管();
    let 選別 = 選別を作る(&保管);
    let mut 受け皿 = Vec::new();
    let 結果 = 選別.線分に触れうる子形状の候補を集める(大域の位置([0.0, 0.0, 0.0]), 大域の位置([200_000.0, 0.0, 0.0]), &mut 受け皿);
    assert_eq!(結果, Err(静的世界の候補の選別エラー::覆いが跨ぐチャンクが多すぎる { 件数: 3126 }));
}

#[test]
fn 有限でない位置の問い合わせは型付きエラーで拒む() {
    let 保管 = 東西に2棟を置いた保管();
    let 選別 = 選別を作る(&保管);
    let mut 受け皿 = Vec::new();
    let 結果 = 選別.線分に触れうる子形状の候補を集める(大域の位置([0.0, f64::NAN, 0.0]), 大域の位置([1.0, 0.0, 0.0]), &mut 受け皿);
    assert_eq!(結果, Err(静的世界の候補の選別エラー::問い合わせの位置が有限でない));
}
