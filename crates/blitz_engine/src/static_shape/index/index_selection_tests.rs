//! 候補の選別そのものの反証。触れる形と触れない形の判別、チャンクを跨ぐ列挙とその並び、同じ入力から同じ並びが出ることを見る。

use super::index_fixture::{保管を組む, 東西に2棟を置いた保管, 衝突対象を作る};
use super::index_probe_fixture::{候補を組へ落とす, 大域の位置, 選別を作る};
use crate::world_query::問い合わせ完全性;
use crate::チャンク座標;

#[test]
fn 覆いに触れる衝突対象だけが候補に挙がる() {
    let 保管 = 東西に2棟を置いた保管();
    let 選別 = 選別を作る(&保管);
    let mut 受け皿 = Vec::new();
    let 完全性 =
        match 選別.線分に触れうる子形状の候補を集める(大域の位置([9.0, 0.0, 0.0]), 大域の位置([11.0, 0.0, 0.0]), &mut 受け皿)
        {
            Ok(完全性) => 完全性,
            Err(誤り) => panic!("候補を集められなかった: {誤り}"),
        };
    assert_eq!(完全性, 問い合わせ完全性::対象範囲を完全に評価できた);
    assert_eq!(候補を組へ落とす(&受け皿), vec![(0, 0, "東の建物".to_string(), 0)]);
}

#[test]
fn チャンクを跨ぐ覆いは座標の昇順に候補を挙げる() {
    let 保管 = 保管を組む(vec![
        (チャンク座標::生成する(1, 0), vec![衝突対象を作る("東隣の建物", &[[4.0, 0.0, 0.0]])]),
        (チャンク座標::生成する(0, 0), vec![衝突対象を作る("手前の建物", &[[60.0, 0.0, 0.0]])]),
    ]);
    let 選別 = 選別を作る(&保管);
    let mut 受け皿 = Vec::new();
    let 完全性 =
        match 選別.線分に触れうる子形状の候補を集める(大域の位置([58.0, 0.0, 0.0]), 大域の位置([70.0, 0.0, 0.0]), &mut 受け皿)
        {
            Ok(完全性) => 完全性,
            Err(誤り) => panic!("候補を集められなかった: {誤り}"),
        };
    assert_eq!(完全性, 問い合わせ完全性::対象範囲を完全に評価できた);
    assert_eq!(
        候補を組へ落とす(&受け皿),
        vec![(0, 0, "手前の建物".to_string(), 0), (1, 0, "東隣の建物".to_string(), 0)]
    );
}

#[test]
fn 同じ入力を2回列挙すると同じ並びが出る() {
    let 保管 = 保管を組む(vec![(
        チャンク座標::生成する(0, 0),
        vec![
            衝突対象を作る("北の建物", &[[10.0, 0.0, 4.0], [10.0, 0.0, 8.0]]),
            衝突対象を作る("南の建物", &[[10.0, 0.0, 12.0]]),
        ],
    )]);
    let 選別 = 選別を作る(&保管);
    let mut 一度目 = Vec::new();
    let mut 二度目 = Vec::new();
    let 始点 = 大域の位置([10.0, 0.0, 0.0]);
    let 終点 = 大域の位置([10.0, 0.0, 20.0]);
    let Ok(_) = 選別.線分に触れうる子形状の候補を集める(始点, 終点, &mut 一度目) else {
        panic!("1度目の列挙に失敗した");
    };
    let Ok(_) = 選別.線分に触れうる子形状の候補を集める(始点, 終点, &mut 二度目) else {
        panic!("2度目の列挙に失敗した");
    };
    assert_eq!(候補を組へ落とす(&一度目), 候補を組へ落とす(&二度目));
    assert_eq!(一度目.len(), 3);
}
