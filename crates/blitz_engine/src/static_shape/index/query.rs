//! 静的世界の候補の選別: 読込済みチャンクの静的物理形状のうち、問い合わせの覆いに触れうる子形状を挙げる操作サービス。
//! 形状の保管とチャンクの格子をコンストラクタで受け取って保持するため、問い合わせの署名に保管も格子の刻みも現れない。
//!
//! 挙げた候補を呼び出し側の受け皿へ積むのは、1回の問い合わせで確保を起こさないためである。受け皿を使い回せば、
//! 2回目以降の問い合わせは確保を1つもしない。判断8の2軸のうち値の軸はその受け皿そのものであり、この操作が返すのは
//! もう一方の軸である完全性だけである。
//!
//! 完全性を候補より先に決められるのは、答えられるかどうかがチャンクが読み込まれているかだけで決まり、候補を1件も見ずに
//! 分かるためである。読み込まれていない座標を覆いが1つでも含めば「評価できない領域を含む」になる。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断8: 問い合わせの値と完全性を別軸にする」

use blitz_collision::shape::大域の軸平行の直方体;
use blitz_math::{メートル, ワールド, 変位, 大域メートル, 大域ワールド位置};

use super::super::storage::チャンクごとの静的物理形状の保管;
use super::candidate::静的な子形状の候補;
use super::error::静的世界の候補の選別エラー;
use crate::world_query::問い合わせ完全性;
use crate::{チャンク一辺, チャンク格子};

/// 覆いに触れうる子形状を、読込済みチャンクの静的物理形状から挙げる操作サービス。
pub struct 静的世界の候補の選別<'形状> {
    保管: &'形状 チャンクごとの静的物理形状の保管,
    格子: チャンク格子,
    チャンクの一辺: 大域メートル,
}

impl<'形状> 静的世界の候補の選別<'形状> {
    /// 読込済みチャンクの形状の保管とチャンクの一辺を受け取って作る。格子と一辺を同じ一辺から導くため、2つが食い違わない。
    pub fn 保管とチャンクの一辺から生成する(
        保管: &'形状 チャンクごとの静的物理形状の保管,
        チャンクの一辺: チャンク一辺,
    ) -> Result<Self, 静的世界の候補の選別エラー> {
        Ok(Self {
            保管,
            格子: チャンク格子::生成する(チャンクの一辺.大域メートルへ変換する())?,
            チャンクの一辺: チャンクの一辺.大域メートルへ変換する(),
        })
    }

    /// 始点から終点へ引いた線分に触れうる子形状の候補を、受け皿へ集める。受け皿は初めに空にする。
    pub fn 線分に触れうる子形状の候補を集める(
        &self,
        始点: 大域ワールド位置,
        終点: 大域ワールド位置,
        受け皿: &mut Vec<静的な子形状の候補<'形状>>,
    ) -> Result<問い合わせ完全性, 静的世界の候補の選別エラー> {
        位置が有限であることを確かめる(始点)?;
        位置が有限であることを確かめる(終点)?;
        let 覆い = 大域の軸平行の直方体::二点に外接する箱を求める(始点, 終点);
        self.覆いに触れる子形状の候補を集める(&覆い, 受け皿)
    }

    /// 軸の両端と半径で決まるカプセルを変位ぶん掃引したとき、触れうる子形状の候補を受け皿へ集める。受け皿は初めに空にする。
    pub fn 掃引したカプセルに触れうる子形状の候補を集める(
        &self,
        軸の始点: 大域ワールド位置,
        軸の終点: 大域ワールド位置,
        半径: メートル,
        掃引の変位: 変位<ワールド>,
        受け皿: &mut Vec<静的な子形状の候補<'形状>>,
    ) -> Result<問い合わせ完全性, 静的世界の候補の選別エラー> {
        位置が有限であることを確かめる(軸の始点)?;
        位置が有限であることを確かめる(軸の終点)?;
        if !半径.値().is_finite() || 半径.値() < 0.0 {
            return Err(静的世界の候補の選別エラー::カプセルの半径が0以上の有限値でない);
        }
        if [掃引の変位.x(), 掃引の変位.y(), 掃引の変位.z()]
            .into_iter()
            .any(|成分| !成分.値().is_finite())
        {
            return Err(静的世界の候補の選別エラー::掃引の変位が有限でない);
        }
        let 覆い = 大域の軸平行の直方体::二点に外接する箱を求める(軸の始点, 軸の終点)
            .全方向へ広げた箱を求める(半径)
            .変位で掃いた箱を求める(掃引の変位);
        self.覆いに触れる子形状の候補を集める(&覆い, 受け皿)
    }

    pub(super) fn 保管(&self) -> &'形状 チャンクごとの静的物理形状の保管 {
        self.保管
    }

    pub(super) fn 格子(&self) -> チャンク格子 {
        self.格子
    }

    pub(super) fn チャンクの一辺(&self) -> 大域メートル {
        self.チャンクの一辺
    }
}

// 覆いを組む前に、与えられた位置の3成分が有限であることを確かめる。天頂の成分はチャンクの座標へ写す計算に現れないため、
// ここで見なければ有限でない天頂が黙って「何とも交わらない覆い」になる。
fn 位置が有限であることを確かめる(位置: 大域ワールド位置) -> Result<(), 静的世界の候補の選別エラー> {
    if [位置.x(), 位置.y(), 位置.z()].into_iter().any(|成分| !成分.値().is_finite()) {
        return Err(静的世界の候補の選別エラー::問い合わせの位置が有限でない);
    }
    Ok(())
}
