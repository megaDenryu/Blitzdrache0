//! 静的な子形状の候補: 粗い選別が「この子形状には触れうる」と答えた1件である。
//!
//! 触れることが確定した当たりではない。包む箱どうしが重なったというだけであり、直方体そのものとの厳密な交差は
//! 詳細判定(実装順6の一般凸形状)が答える。名前が「候補」であるのはそのためである。
//!
//! 親の綴りと子形状を参照で持つのは、1回の問い合わせが数十件を挙げうるのに対し、綴りが可変長の文字列であり、
//! 値で持つと候補1件ごとに確保が起きるためである。参照の寿命は形状の保管の寿命であり、チャンクが解除されるまで生きる。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断9: 複合形状は子形状を束ねて1つの衝突対象にする」

use blitz_collision::shape::任意姿勢の直方体;

use super::super::child_shape::衝突対象の子形状;
use super::super::child_shape_identifier::子形状識別子;
use super::super::object_identifier::衝突対象の安定識別子;
use crate::チャンク座標;

/// 粗い選別が挙げた、触れうる子形状1件。どのチャンクのどの衝突対象のどの子形状かと、その形を答える。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 静的な子形状の候補<'形状> {
    チャンク座標: チャンク座標,
    衝突対象の安定識別子: &'形状 衝突対象の安定識別子,
    子形状: &'形状 衝突対象の子形状,
}

impl<'形状> 静的な子形状の候補<'形状> {
    /// 候補を挙げた走査だけが呼ぶ。3つはどれも自分の不変条件を満たしているため、ここでの検査は要らない。
    pub(super) fn 生成する(
        チャンク座標: チャンク座標,
        衝突対象の安定識別子: &'形状 衝突対象の安定識別子,
        子形状: &'形状 衝突対象の子形状,
    ) -> Self {
        Self {
            チャンク座標,
            衝突対象の安定識別子,
            子形状,
        }
    }

    /// この候補が住むチャンクの座標。形の座標が群のローカル空間であるため、大域へ写すにはこの座標が要る。
    pub fn チャンク座標(&self) -> チャンク座標 {
        self.チャンク座標
    }

    /// この子形状が属する衝突対象をチャンクの中で指す綴り。
    pub fn 衝突対象の安定識別子(&self) -> &'形状 衝突対象の安定識別子 {
        self.衝突対象の安定識別子
    }

    /// この子形状を衝突対象の中で指す番号。
    pub fn 子形状識別子(&self) -> 子形状識別子 {
        self.子形状.識別子()
    }

    /// この子形状の形そのものである、群のローカル空間の直方体。詳細判定はこれを相手にする。
    pub fn 直方体(&self) -> 任意姿勢の直方体 {
        self.子形状.直方体()
    }
}
