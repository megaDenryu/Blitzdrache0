//! 読込済みチャンクを辿って候補を積み上げる工程。受け取るのは覆いと受け皿、返すのは覆いのどこまでを調べられたかの完全性である。
//!
//! 覆いが跨ぐ座標だけを見るのではなく読込済みチャンクを全部見るのは、子形状を包む箱が所有チャンクの区画へ収まる保証が
//! 無いためである。一辺64メートルのチャンク(0,0)の東63メートルに半分の長さ1メートルの箱を置くと、その箱は東64メートル
//! すなわち隣のチャンクの区画へ張り出す。覆いが跨ぐ座標を数え上げる形では、東64メートルの問い合わせがチャンク(1,0)だけを
//! 見てこの箱を落とす。読込済みチャンクは高々数百件であり、1件あたりの費用はチャンクの全衝突対象を包む箱1つとの比較で
//! あるから、全部を見る費用は覆いの広さにも張り出しの大きさにも依らない。
//!
//! 読み込まれていない座標で走査を止めないのは、この問い合わせが最初の当たりでなく範囲の列挙であり、手前で止めても
//! 答えが確定しないためである。止めずに完全性を落として先へ進み、読めた範囲の候補は挙げる。
//!
//! 注意: 完全性が答えるのは「覆いの触れる区域が1つ残らず読み込まれているか」までである。読み込まれていないチャンクに
//! 属する形が覆いまで張り出していても、その形は実行中のどこにも存在しないため、ここから見えない。覆いが読込済みの
//! 区域だけに収まっていれば完全性は落ちないが、その外から張り出す形は答えに入らない。これは張り出しの上界を仮定
//! しない限り塞げず、上界を仮定すると外れたときに黙って候補が落ちるため、仮定を置かずに限界として書く。
//!
//! 階層を作らず平坦に辿るのは、1チャンクの衝突対象が高々数十件であり、走査の費用が覆いの広さに比例したまま収まるためである。
//! この数十件は実測で保証された値ではなく、切り替える条件が立つまでの定性的な前提である。木を作る費用と焼き込みの版の
//! 複雑さに見合わない。切り替える条件は測って決める。1チャンクの衝突対象数が実測で選別を予算の主要因にした日に、
//! 判断11の階層(全体の粗い境界から中間領域の境界群を経て少数の葉へ至る木)へ移す。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断11: 静的衝突メッシュは階層を持ち、事前生成を基本とする」

use blitz_collision::shape::大域の軸平行の直方体;

use super::super::chunk_shapes::チャンクの静的物理形状;
use super::candidate::静的な子形状の候補;
use super::chunk_span::覆いが跨ぐチャンク座標の矩形;
use super::error::静的世界の候補の選別エラー;
use super::query::静的世界の候補の選別;
use crate::world_query::問い合わせ完全性;
use crate::チャンク座標;

impl<'形状> 静的世界の候補の選別<'形状> {
    // 読込済みチャンクを座標の昇順に辿って候補を積み、あわせて覆いの矩形に入る読込済みチャンクを数える。数えた件数が
    // 矩形のチャンク件数に足りなければ、覆いの中に読み込まれていない区域がある。世界にそもそも存在しない座標も同じ枝に
    // なる。呼び出し側がその2つに対して取る行動は同じである。
    // 前提: 受け皿は公開の入口が既に空にしている。ここで空にし直すと、入力の検査で返った問い合わせの受け皿だけが
    // 空にならない形へ戻る。
    pub(super) fn 覆いに触れる子形状の候補を集める(
        &self,
        覆い: &大域の軸平行の直方体,
        受け皿: &mut Vec<静的な子形状の候補<'形状>>,
    ) -> Result<問い合わせ完全性, 静的世界の候補の選別エラー> {
        let 矩形 = 覆いが跨ぐチャンク座標の矩形::覆いと格子から求める(覆い, self.格子())?;
        let mut 矩形に入る読込済みの件数 = 0_u128;
        for (座標, 形状) in self.保管().座標の昇順で数え上げる() {
            if 矩形.座標を含むか(座標) {
                矩形に入る読込済みの件数 += 1;
            }
            self.チャンク1つの候補を集める(座標, 形状, 覆い, 受け皿);
        }
        Ok(if 矩形に入る読込済みの件数 == 矩形.チャンク件数() {
            問い合わせ完全性::対象範囲を完全に評価できた
        } else {
            問い合わせ完全性::評価できない領域を含む
        })
    }

    // 1つのチャンクの中を、衝突対象を焼いた順・子形状を据えた順に辿る。チャンクの全衝突対象を包む箱が覆いと交わらなければ
    // 衝突対象を1件も、衝突対象の包む箱が交わらなければその対象の子形状を1件も調べない。
    fn チャンク1つの候補を集める(
        &self,
        座標: チャンク座標,
        形状: &'形状 チャンクの静的物理形状,
        覆い: &大域の軸平行の直方体,
        受け皿: &mut Vec<静的な子形状の候補<'形状>>,
    ) {
        let 大域原点 = 座標.大域原点を求める(self.チャンクの一辺());
        let Some(チャンクの箱) = 形状.全衝突対象を包む軸平行の直方体() else {
            return;
        };
        if !覆い.相手と交わるか(&大域の軸平行の直方体::局所の箱を大域原点から写して求める(
            大域原点,
            &チャンクの箱,
        )) {
            return;
        }
        for 対象 in 形状.衝突対象一覧() {
            let 対象の箱 =
                大域の軸平行の直方体::局所の箱を大域原点から写して求める(大域原点, &対象.外接する軸平行の直方体());
            if !覆い.相手と交わるか(&対象の箱) {
                continue;
            }
            for 子形状 in 対象.子形状一覧() {
                let 子形状の箱 =
                    大域の軸平行の直方体::局所の箱を大域原点から写して求める(大域原点, &子形状.外接する軸平行の直方体());
                if 覆い.相手と交わるか(&子形状の箱) {
                    受け皿.push(静的な子形状の候補::生成する(座標, 大域原点, 対象.安定識別子(), 子形状));
                }
            }
        }
    }
}
