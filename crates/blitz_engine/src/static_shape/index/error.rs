//! 静的世界の候補の選別が答えられないときの失敗。
//!
//! 「読み込まれていないチャンクを覆いが含む」はここに入らない。それは値が壊れたのではなく、覆いのどこまでを
//! 調べられたかの話であり、`問い合わせ完全性`が別の軸で表す。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断8: 問い合わせの値と完全性を別軸にする」

use super::chunk_span::覆いが跨げるチャンクの上限件数;
use crate::チャンク格子エラー;

/// 候補の選別が拒否する理由。
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum 静的世界の候補の選別エラー {
    /// チャンクの一辺から格子を組めないか、覆いの端をチャンクの座標へ写せない。
    #[error("覆いをチャンクの格子へ写せない: {0}")]
    覆いを格子へ写せない(#[from] チャンク格子エラー),
    /// 覆いが跨ぐチャンクの件数が、平坦な選別が受け付ける上限を越えた。
    #[error(
        "覆いが跨ぐチャンクが{件数}件あり、平坦な選別が受け付ける上限{}件を越えた",
        覆いが跨げるチャンクの上限件数
    )]
    覆いが跨ぐチャンクが多すぎる {
        /// 覆いが跨ぐと数えたチャンクの件数。
        件数: i64,
    },
    /// 問い合わせが与えた位置に有限でない成分が含まれる。
    #[error("問い合わせの位置に有限でない成分が含まれる")]
    問い合わせの位置が有限でない,
    /// カプセルの半径が0以上の有限値でない。
    #[error("カプセルの半径が0以上の有限値でない")]
    カプセルの半径が0以上の有限値でない,
    /// 掃引の変位に有限でない成分が含まれる。
    #[error("掃引の変位に有限でない成分が含まれる")]
    掃引の変位が有限でない,
}
