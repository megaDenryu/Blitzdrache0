//! 受け皿の契約の反証。公開の入口が「受け皿は入力を検査するより先に空にする」と約束しているため、型付きエラーで
//! 返った問い合わせの受け皿にも前の候補が残らないことを、2つの入口それぞれで見る。
//!
//! 前の問い合わせで候補を積んだ受け皿をそのまま失敗する問い合わせへ渡すのは、空にする位置が入力の検査より後ろに
//! あるとこの形でだけ違いが出るためである。空の受け皿から始めると、どちらの位置でも結果が空になって区別が付かない。

use blitz_math::メートル;

use super::index_fixture::{大域の位置, 東へ進む変位, 東西に2棟を置いた保管, 選別を作る};
use super::{静的な子形状の候補, 静的世界の候補の選別, 静的世界の候補の選別エラー};

fn 候補を1件積んだ受け皿を作る<'形状>(選別: &静的世界の候補の選別<'形状>) -> Vec<静的な子形状の候補<'形状>> {
    let mut 受け皿 = Vec::new();
    let Ok(_) = 選別.線分に触れうる子形状の候補を集める(大域の位置([9.0, 0.0, 0.0]), 大域の位置([11.0, 0.0, 0.0]), &mut 受け皿)
    else {
        panic!("候補を積む問い合わせに失敗した");
    };
    assert_eq!(受け皿.len(), 1);
    受け皿
}

#[test]
fn 線分の問い合わせが型付きエラーで返るとき受け皿は空である() {
    let 保管 = 東西に2棟を置いた保管();
    let 選別 = 選別を作る(&保管);
    let mut 受け皿 = 候補を1件積んだ受け皿を作る(&選別);
    let 結果 =
        選別.線分に触れうる子形状の候補を集める(大域の位置([f64::INFINITY, 0.0, 0.0]), 大域の位置([1.0, 0.0, 0.0]), &mut 受け皿);
    assert_eq!(結果, Err(静的世界の候補の選別エラー::問い合わせの位置が有限でない));
    assert!(受け皿.is_empty(), "型付きエラーで返った受け皿に前の候補が残っている");
}

#[test]
fn 掃引の問い合わせが型付きエラーで返るとき受け皿は空である() {
    let 保管 = 東西に2棟を置いた保管();
    let 選別 = 選別を作る(&保管);
    let mut 受け皿 = 候補を1件積んだ受け皿を作る(&選別);
    let 結果 = 選別.掃引したカプセルに触れうる子形状の候補を集める(
        大域の位置([9.0, 0.0, 0.0]),
        大域の位置([11.0, 0.0, 0.0]),
        メートル::生成する(-1.0),
        東へ進む変位(1.0),
        &mut 受け皿,
    );
    assert_eq!(結果, Err(静的世界の候補の選別エラー::カプセルの半径が0以上の有限値でない));
    assert!(受け皿.is_empty(), "型付きエラーで返った受け皿に前の候補が残っている");
}
