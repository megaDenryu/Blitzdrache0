//! 静的な衝突対象: 建物1棟のように、複数の子形状を束ねて1つとして扱う、動かない物体。
//!
//! 子形状を1件も持たない衝突対象を拒むのは、当たりようのない物体が集まりに載ると、問い合わせが返す「当たらなかった」が
//! 「そこに何も無い」と「そこに形の無い物がある」の2つの意味を持つためである。
//!
//! 子形状識別子の重複を拒むのは、答えが指す子形状が一意に決まらなくなるためである。
//!
//! 子形状の中心をチャンクの基準原点からの許容範囲で拒むのは、この物体が個体配置で据えた部品から作られ、その配置と
//! 同じ空間に住むためである。形そのものの型(`任意姿勢の直方体`)はこの範囲を課さない。衝突数学層は世界もチャンクも
//! 知らないためであり、範囲を課すのは形を世界の物体へ束ねるこの地点である。焼き込みの側も実行時形式の読み取りの側も
//! この生成を通るため、入口が2つに割れない。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断9: 複合形状は子形状を束ねて1つの衝突対象にする」

use blitz_collision::shape::軸平行の直方体;
use blitz_math::ローカル;

use super::child_shape::衝突対象の子形状;
use super::error::{軸名一覧, 静的物理形状エラー};
use super::object_identifier::衝突対象の安定識別子;
use crate::asset::チャンクの基準原点からの許容メートル;

/// 建物1棟のように、複数の子形状を束ねて1つとして扱う、動かない物体。
#[derive(Debug, Clone, PartialEq)]
pub struct 静的な衝突対象 {
    安定識別子: 衝突対象の安定識別子,
    子形状一覧: Vec<衝突対象の子形状>,
    外接する軸平行の直方体: 軸平行の直方体<ローカル>,
}

impl 静的な衝突対象 {
    /// 子形状が空であること、子形状識別子の重複、および子形状の中心がチャンクの基準原点から離れすぎていることを
    /// 型付きエラーで拒む。全部の子形状を包む箱をここで1度だけ合成する。
    pub fn 安定識別子と子形状一覧から生成する(
        安定識別子: 衝突対象の安定識別子,
        子形状一覧: Vec<衝突対象の子形状>,
    ) -> Result<Self, 静的物理形状エラー> {
        if 子形状一覧.is_empty() {
            return Err(静的物理形状エラー::子形状が空);
        }
        for (添字, 子形状) in 子形状一覧.iter().enumerate() {
            let 先に同じ番号がある = 子形状一覧[..添字].iter().any(|先の子形状| 先の子形状.識別子() == 子形状.識別子());
            if 先に同じ番号がある {
                return Err(静的物理形状エラー::子形状識別子が重複する {
                    番号: 子形状.識別子().番号を返す(),
                });
            }
            中心がチャンクの基準原点の近くに在ることを確かめる(子形状)?;
        }
        let Some(外接する軸平行の直方体) = 子形状の箱をすべて包む箱を求める(&子形状一覧) else {
            return Err(静的物理形状エラー::子形状が空);
        };
        Ok(Self {
            安定識別子,
            子形状一覧,
            外接する軸平行の直方体,
        })
    }

    /// この衝突対象をチャンクの中で指す綴り。
    pub fn 安定識別子(&self) -> &衝突対象の安定識別子 {
        &self.安定識別子
    }

    /// この衝突対象を成す子形状を、部品を据えた順に並べたもの。
    pub fn 子形状一覧(&self) -> &[衝突対象の子形状] {
        &self.子形状一覧
    }

    /// 全部の子形状を包む、群のローカル空間で軸平行の直方体。空間索引の1段目の選別がこれを見る。
    pub fn 外接する軸平行の直方体(&self) -> 軸平行の直方体<ローカル> {
        self.外接する軸平行の直方体
    }
}

// 子形状の直方体の中心が、個体配置と同じ許容範囲に収まっているかを軸ごとに見る。
fn 中心がチャンクの基準原点の近くに在ることを確かめる(
    子形状: &衝突対象の子形状
) -> Result<(), 静的物理形状エラー> {
    let 中心 = 子形状.直方体().中心();
    for (軸, 値) in 軸名一覧.into_iter().zip([中心.x(), 中心.y(), 中心.z()]) {
        if 値.値().abs() > チャンクの基準原点からの許容メートル {
            return Err(静的物理形状エラー::中心が範囲外 { 軸 });
        }
    }
    Ok(())
}

// 子形状の包む箱を順に畳んだ箱。1件も無ければ包む箱が定まらないため値なしを返す。
fn 子形状の箱をすべて包む箱を求める(子形状一覧: &[衝突対象の子形状]) -> Option<軸平行の直方体<ローカル>> {
    子形状一覧
        .iter()
        .map(衝突対象の子形状::外接する軸平行の直方体)
        .reduce(|畳んだ箱, 次の箱| 畳んだ箱.相手を含む箱を求める(&次の箱))
}
