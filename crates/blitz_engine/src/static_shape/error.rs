//! 静的物理形状の値が満たすべき条件を破ったときの失敗。
//!
//! 注意: この型はアセット実行時形式エラーへ合流するため、そちらと同じく`Copy`と`Eq`を導出できる形に保つ。
//! 破れた成分は値ではなく軸の名前で示す。
//!
//! 形そのものの破れ(中心が有限でない・半分の長さが負である等)は衝突数学層の`直方体の生成エラー`が持ち、
//! この型はそれを包んで運ぶ。ここに残るのは世界の側の条件、すなわちチャンクの中での位置の範囲と識別子の一意性である。

use blitz_collision::shape::直方体の生成エラー;

use crate::asset::チャンクの基準原点からの許容メートル;

/// 静的物理形状の生成が拒否する理由。
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum 静的物理形状エラー {
    /// 形そのものが直方体として成り立たない。
    #[error("形が直方体として成り立たない: {0}")]
    直方体として成り立たない(#[from] 直方体の生成エラー),
    /// 子形状の直方体の中心がチャンクの基準原点からの許容範囲を超えた。
    #[error(
        "子形状の直方体の中心の{軸}成分がチャンクの基準原点からの許容範囲{}メートルを超えた",
        チャンクの基準原点からの許容メートル
    )]
    中心が範囲外 { 軸: &'static str },
    /// 直方体の回転を単位クォータニオンへ正規化できない。
    #[error("直方体の回転クォータニオンを正規化できない")]
    回転を正規化できない,
    /// 衝突対象の安定識別子の綴りが空である。
    #[error("衝突対象の安定識別子が空である")]
    安定識別子が空,
    /// 衝突対象の安定識別子が正準化されていない綴りで渡された。
    #[error("衝突対象の安定識別子の前後に空白が付いており、正準化が済んでいない")]
    安定識別子が前後に空白を持つ,
    /// 1つのチャンクの中で衝突対象の安定識別子が重複している。
    #[error("1つのチャンクの中で衝突対象の安定識別子が重複している")]
    安定識別子が重複する,
    /// 1つの衝突対象の中で子形状識別子が重複している。
    #[error("1つの衝突対象の中で子形状識別子{番号}が重複している")]
    子形状識別子が重複する { 番号: u32 },
    /// 衝突対象が子形状を1件も持たない。
    #[error("衝突対象が子形状を1つも持たない")]
    子形状が空,
    /// 静的物理形状の節を持たない旧版の並びで、形状を持つシーンを焼こうとした。
    #[error("静的物理形状を持つシーンを、その節を持たない旧版の並びで焼こうとした")]
    節を持たない旧版で焼こうとした,
}

/// 3成分の値のうちどれが破れたかを示す名前。エラーが値を持てないため位置で示す。
pub(super) const 軸名一覧: [&str; 3] = ["X", "Y", "Z"];
