//! 静的物理形状の値が満たすべき条件を破ったときの失敗。
//!
//! 注意: この型はアセット実行時形式エラーへ合流するため、そちらと同じく`Copy`と`Eq`を導出できる形に保つ。
//! 破れた成分は値ではなく軸の名前で示す。

use crate::asset::チャンクの基準原点からの許容メートル;

/// 静的物理形状の生成が拒否する理由。
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum 静的物理形状エラー {
    #[error("直方体の中心の{軸}成分に有限でない値が含まれる")]
    中心が有限でない { 軸: &'static str },
    #[error(
        "直方体の中心の{軸}成分がチャンクの基準原点からの許容範囲{}メートルを超えた",
        チャンクの基準原点からの許容メートル
    )]
    中心が範囲外 { 軸: &'static str },
    #[error("直方体の軸ごとの半分の長さの{軸}成分が負であるか有限でない")]
    半分の長さが負か非有限 { 軸: &'static str },
    #[error("直方体の回転クォータニオンを正規化できない")]
    回転を正規化できない,
    #[error("衝突対象の安定識別子が空である")]
    安定識別子が空,
    #[error("1つのチャンクの中で衝突対象の安定識別子が重複している")]
    安定識別子が重複する,
    #[error("1つの衝突対象の中で子形状識別子{番号}が重複している")]
    子形状識別子が重複する { 番号: u32 },
    #[error("衝突対象が子形状を1つも持たない")]
    子形状が空,
    #[error("静的物理形状を持つシーンを、その節を持たない旧版の並びで焼こうとした")]
    節を持たない旧版で焼こうとした,
}

/// 3成分の値のうちどれが破れたかを示す名前。エラーが値を持てないため位置で示す。
pub(super) const 軸名一覧: [&str; 3] = ["X", "Y", "Z"];
