//! 静的世界の空間索引: 問い合わせの覆いに触れうる静的な子形状の候補を、粗い境界だけで選び出す。
//!
//! 二段構えである。1段目はチャンクであり、読み込まれているチャンクを座標の昇順に辿って、そのチャンクの全衝突対象を
//! 包む箱を覆いと比べる。2段目はチャンクの中であり、衝突対象ごとの外接する軸平行の直方体、次にその子形状ごとの箱を、
//! 覆いと比べる。ここが答えるのは候補までであり、直方体そのものとの厳密な交差は詳細判定(実装順6の一般凸形状)が答える。
//!
//! 1段目を「覆いが跨ぐ座標の数え上げ」にしないのは、子形状を包む箱が所有チャンクの区画へ収まる保証が無く、隣の
//! チャンクから張り出した形を落とすためである。理由と費用は `query_gather.rs` にある。
//!
//! 2段目に階層(判断11の木)を作らないのは、判断11の階層が静的「メッシュ」すなわち崖や洞窟のような三角形の網へ向けた
//! ものであり、建物の衝突対象は1チャンクに高々数十件であるためである。この数十件は実測で保証された値ではなく、
//! 切り替える条件が立つまでの定性的な前提である。数十件の平坦な比較は覆いの広さに比例したまま収まり、木を作る費用と
//! 焼き込みの版の複雑さに見合わない。切り替える条件は測って決める。1チャンクの衝突対象数が実測で選別を予算の
//! 主要因にした日に、判断11の階層へ移す。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断11: 静的衝突メッシュは階層を持ち、事前生成を基本とする」
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断12: 空間探索は粗い候補選別と詳細判定を責務として分け、世界は二段構えで辿る」

