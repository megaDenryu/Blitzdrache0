//! 静的世界の空間索引: 問い合わせの覆いに触れうる静的な子形状の候補を、粗い境界だけで選び出す。
//!
//! 二段構えである。1段目はチャンクであり、覆いが跨ぐチャンクの座標を数え上げて、読み込まれている座標の形だけを見る。
//! 2段目はチャンクの中であり、衝突対象ごとの外接する軸平行の直方体、次にその子形状ごとの箱を、覆いと比べる。
//! ここが答えるのは候補までであり、直方体そのものとの厳密な交差は詳細判定(実装順6の一般凸形状)が答える。
//!
//! 2段目に階層(判断11の木)を作らないのは、判断11の階層が静的「メッシュ」すなわち崖や洞窟のような三角形の網へ向けた
//! ものであり、建物の衝突対象は1チャンクに高々数十件であるためである。数十件の平坦な比較は覆いの広さに比例したまま
//! 収まり、木を作る費用と焼き込みの版の複雑さに見合わない。切り替える条件は測って決める。1チャンクの衝突対象数が
//! 実測で選別を予算の主要因にした日に、判断11の階層へ移す。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断11: 静的衝突メッシュは階層を持ち、事前生成を基本とする」
