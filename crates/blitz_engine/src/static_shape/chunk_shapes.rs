//! チャンクの静的物理形状: 1つのチャンクに属する静的な衝突対象をすべて束ねた集まり。
//!
//! チャンクを単位にするのは、この集まりがチャンクの読込で載りチャンクの解除で消える寿命を持つためである。
//! 空の集まりを作れるのは、建物を1棟も置かないチャンクと、静的物理形状を焼く前の版で焼かれたチャンクがあるためであり、
//! これは既定値の無言の適用ではなく「静的な衝突対象が0件である」という事実そのものである。
//!
//! 全衝突対象を包む箱を持たせるのは、空間索引の1段目が読込済みチャンクを1つずつ見るためである。読込のときに1度だけ
//! 合成し、問い合わせのたびには合成しない。0件の集まりには包む箱が無く、値なしで答える。「箱の無いチャンク」と
//! 「どことも交わらない箱を持つチャンク」を同じ形にしないためである。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断12: 空間探索は粗い候補選別と詳細判定を責務として分け、世界は二段構えで辿る」

use blitz_collision::shape::軸平行の直方体;
use blitz_math::ローカル;

use super::child_shape::衝突対象の子形状;
use super::collision_object::静的な衝突対象;
use super::error::静的物理形状エラー;
use super::object_identifier::衝突対象の安定識別子;

/// 1つのチャンクに属する静的な衝突対象をすべて束ねた集まり。
#[derive(Debug, Clone, PartialEq)]
pub struct チャンクの静的物理形状 {
    衝突対象一覧: Vec<静的な衝突対象>,
    全衝突対象を包む軸平行の直方体: Option<軸平行の直方体<ローカル>>,
}

impl チャンクの静的物理形状 {
    /// 安定識別子の重複を拒む。重複すると問い合わせの答えがどの物体を指すか一意に決まらない。
    /// 全衝突対象を包む箱をここで1度だけ合成する。
    pub fn 衝突対象一覧から生成する(衝突対象一覧: Vec<静的な衝突対象>) -> Result<Self, 静的物理形状エラー> {
        for (添字, 対象) in 衝突対象一覧.iter().enumerate() {
            let 先に同じ綴りがある = 衝突対象一覧[..添字].iter().any(|先の対象| 先の対象.安定識別子() == 対象.安定識別子());
            if 先に同じ綴りがある {
                return Err(静的物理形状エラー::安定識別子が重複する);
            }
        }
        let 全衝突対象を包む軸平行の直方体 = 衝突対象の箱をすべて包む箱を求める(&衝突対象一覧);
        Ok(Self {
            衝突対象一覧,
            全衝突対象を包む軸平行の直方体,
        })
    }

    /// 静的な衝突対象を1件も持たない集まり。建物を1棟も置かないチャンクがこれになる。
    pub fn 空を作る() -> Self {
        Self {
            衝突対象一覧: Vec::new(),
            全衝突対象を包む軸平行の直方体: None,
        }
    }

    /// このチャンクの全衝突対象を包む、群のローカル空間で軸平行の直方体。衝突対象が0件なら値なしを返す。
    /// 空間索引の1段目の選別がこれを見る。
    pub fn 全衝突対象を包む軸平行の直方体(&self) -> Option<軸平行の直方体<ローカル>> {
        self.全衝突対象を包む軸平行の直方体
    }

    /// 束ねている静的な衝突対象を、取り込んだ順に並べたもの。
    pub fn 衝突対象一覧(&self) -> &[静的な衝突対象] {
        &self.衝突対象一覧
    }

    /// 束ねている静的な衝突対象の件数。
    pub fn 衝突対象数(&self) -> usize {
        self.衝突対象一覧.len()
    }

    /// 全衝突対象の子形状を合わせた件数。
    pub fn 子形状の総数(&self) -> usize {
        self.衝突対象一覧.iter().map(|対象| 対象.子形状一覧().len()).sum()
    }

    /// 親の安定識別子を添えて子形状を1件ずつ数え上げる。**問い合わせの側が形状を辿る唯一の口である。**
    /// 親を添えるのは、答えが親の衝突対象識別子と子形状識別子の両方を返せなければならないためである。
    pub fn 親を添えて子形状を数え上げる(&self) -> impl Iterator<Item = (&衝突対象の安定識別子, &衝突対象の子形状)> {
        self.衝突対象一覧
            .iter()
            .flat_map(|対象| 対象.子形状一覧().iter().map(move |子形状| (対象.安定識別子(), 子形状)))
    }
}

// 衝突対象の包む箱を順に畳んだ箱。1件も無ければ包む箱が定まらないため値なしを返す。
fn 衝突対象の箱をすべて包む箱を求める(衝突対象一覧: &[静的な衝突対象]) -> Option<軸平行の直方体<ローカル>> {
    衝突対象一覧
        .iter()
        .map(静的な衝突対象::外接する軸平行の直方体)
        .reduce(|畳んだ箱, 次の箱| 畳んだ箱.相手を含む箱を求める(&次の箱))
}
