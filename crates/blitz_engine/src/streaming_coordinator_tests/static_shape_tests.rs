//! チャンクの読込と解除に合わせて静的物理形状が出入りすることの試験。
//!
//! 「実行中に世界の静的形状が問い合わせ可能なデータとして存在する」という要求は、形状が焼けることだけでは満たせない。
//! 読み込まれていないチャンクの形状を答えないこと、解除したチャンクの形状を答え続けないことまでが要求である。

use crate::streaming_chunk_world_fixture::{後始末する, 静的物理形状を載せた世界を作る};
use crate::streaming_coordinator_fixture::{常駐まで進める, 準備完了を待つ, 起動する, 進める};
use crate::{ストリーミングメモリ量, チャンク座標};

#[test]
fn 常駐したチャンクの形状を座標で引ける() {
    let (パス一覧, カタログ, 目録) = 静的物理形状を載せた世界を作る("static_shape_load", &[(0, 0), (1, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(200_000, 200_000), 1);
    常駐まで進める(&mut 調停, &カタログ, 50.0, 2);
    assert_eq!(調停.静的物理形状を持つチャンク数(), 2);
    let Some(形状) = 調停.静的物理形状を引く(チャンク座標::生成する(1, 0)) else {
        panic!("常駐したチャンクの静的物理形状を引けなかった");
    };
    let 組一覧: Vec<(String, u32)> = 形状
        .親を添えて子形状を数え上げる()
        .map(|(親, 子)| (親.綴り().to_string(), 子.識別子().番号を返す()))
        .collect();
    assert_eq!(組一覧, vec![("酒場".to_string(), 0), ("酒場".to_string(), 1)]);
    assert!(調停.静的物理形状を引く(チャンク座標::生成する(5, 5)).is_none());
    後始末する(&パス一覧);
}

#[test]
fn gpuへ渡すシーンは形状を運ばない() {
    let (パス一覧, カタログ, 目録) = 静的物理形状を載せた世界を作る("static_shape_handoff", &[(0, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(200_000, 200_000), 1);
    準備完了を待つ(&mut 調停, &カタログ, 50.0, 1);
    let Ok(Some(シーン)) = 調停.gpu転送のためにシーンデータを取り出す(チャンク座標::生成する(0, 0)) else {
        panic!("準備済みチャンクのシーンデータを取り出せなかった");
    };
    assert_eq!(シーン.静的物理形状().衝突対象数(), 0);
    assert_eq!(調停.静的物理形状を持つチャンク数(), 1);
    後始末する(&パス一覧);
}

#[test]
fn gpu資源の解除を報告すると形状が消える() {
    let (パス一覧, カタログ, 目録) = 静的物理形状を載せた世界を作る("static_shape_release", &[(0, 0), (1, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(200_000, 200_000), 1);
    常駐まで進める(&mut 調停, &カタログ, 50.0, 2);
    let 離脱 = 進める(&mut 調停, &カタログ, 100_050.0);
    // 解除待ちへ移っただけでは台帳の記録が残るため形状も残る。外すのは台帳から記録が消える実破棄の報告の地点である。
    assert_eq!(調停.静的物理形状を持つチャンク数(), 2);
    for 座標 in 離脱.gpu資源解除待ち一覧() {
        if let Err(誤り) = 調停.gpu資源の解除を報告する(*座標) {
            panic!("GPU資源の解除を報告できなかった: {誤り}");
        }
    }
    assert_eq!(調停.静的物理形状を持つチャンク数(), 0);
    後始末する(&パス一覧);
}

#[test]
fn 準備済みのまま不要になったチャンクの形状も消える() {
    let (パス一覧, カタログ, 目録) = 静的物理形状を載せた世界を作る("static_shape_discard", &[(0, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(200_000, 200_000), 1);
    準備完了を待つ(&mut 調停, &カタログ, 50.0, 1);
    assert_eq!(調停.静的物理形状を持つチャンク数(), 1);
    let 離脱 = 進める(&mut 調停, &カタログ, 100_050.0);
    assert_eq!(離脱.cpuデータ破棄一覧(), [チャンク座標::生成する(0, 0)]);
    assert_eq!(調停.静的物理形状を持つチャンク数(), 0);
    後始末する(&パス一覧);
}

#[test]
fn リセットで形状を捨てる() {
    let (パス一覧, カタログ, 目録) = 静的物理形状を載せた世界を作る("static_shape_reset", &[(0, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(200_000, 200_000), 1);
    常駐まで進める(&mut 調停, &カタログ, 50.0, 1);
    調停.リセットする();
    assert_eq!(調停.静的物理形状を持つチャンク数(), 0);
    後始末する(&パス一覧);
}
