//! 検査が選択を1回走らせるための呼び出し。受け取るのは視錐台と材料と基準原点、返すのは計数とID列である。
//! 段を1つだけ持つ群として走らせるのは、段が1つなら選択の結果が可視判定だけで決まり、可視判定の振る舞いが露わになるためである。

use blitz_math::{カメラ相対位置, メートル};

use crate::{
    個体LOD選択設定, 個体別段状態, 個体詳細段, 個体選択材料, 可視個体と段の選別係, 可視判定方式, 可視判定計数, 段選択方式, 群可視材料, 視錐台,
    距離区分別の光空間直方体, 距離区分別の可視判定,
};

/// 段を1つだけ持つ群として選ぶ。段が1つなら選択の結果は可視判定だけで決まるため、この呼び出しは可視判定の振る舞いを露わにする。
/// 返すのは計数と、その群のID列のうちシーンパスの区間に置かれた個体の並びである。
pub(super) fn 単段で選ぶ(
    視錐台: &視錐台, 材料: &群可視材料, 基準原点: カメラ相対位置
) -> (可視判定計数, Vec<u32>) {
    let mut 選別係 = 可視個体と段の選別係::生成する();
    let 計数 = 単段で選別係へ選ぶ(視錐台, 材料, 基準原点, &mut 選別係);
    (計数, 可視部分(&選別係, 0, 計数.シーン可視数()))
}

/// 選別係を呼び出し元が持つ形。複数の群を1本の列へ連ねる振る舞いを見る検査が使う。
/// 影の側をどの距離区分も全個体可視に固定するのは、この検査群が見るのがカメラ視錐台の振る舞いだけであり、
/// 距離区分ごとの判定が絡む振る舞いは`pass_interval`と`light_box`が別に見るためである。
pub(super) fn 単段で選別係へ選ぶ(
    視錐台: &視錐台,
    材料: &群可視材料,
    基準原点: カメラ相対位置,
    選別係: &mut 可視個体と段の選別係,
) -> 可視判定計数 {
    選別係へ選ぶ(
        可視判定方式::視錐台で絞る(視錐台),
        距離区分別の可視判定::全距離区分で全個体を可視とする,
        材料,
        基準原点,
        選別係,
    )
}

/// シーンにカメラ視錐台、影に距離区分ごとの光空間直方体を与える形。パス別の区間の並びを見る検査が使う。
pub(super) fn 距離区分別で選別係へ選ぶ(
    シーン視錐台: &視錐台,
    距離区分別の直方体: &距離区分別の光空間直方体,
    材料: &群可視材料,
    基準原点: カメラ相対位置,
    選別係: &mut 可視個体と段の選別係,
) -> 可視判定計数 {
    選別係へ選ぶ(
        可視判定方式::視錐台で絞る(シーン視錐台),
        距離区分別の可視判定::距離区分ごとの直方体で絞る {
            直方体: 距離区分別の直方体,
            影の視距離: None,
        },
        材料,
        基準原点,
        選別係,
    )
}

pub(super) fn 選別係へ選ぶ(
    シーン可視判定: 可視判定方式<'_>,
    距離区分別の可視判定: 距離区分別の可視判定<'_>,
    材料: &群可視材料,
    基準原点: カメラ相対位置,
    選別係: &mut 可視個体と段の選別係,
) -> 可視判定計数 {
    let mut 状態 = 個体別段状態::生成する(材料.個体数(), 個体詳細段::最詳細());
    選別係.群1つの可視個体と段を選ぶ(
        &個体選択材料 {
            シーン可視判定,
            距離区分別の可視判定,
            材料,
            カメラ相対の基準原点: 基準原点,
            段選択: 段選択方式::距離とヒステリシス(既定の段設定()),
        },
        &mut 状態,
    )
}

pub(super) fn 既定の段設定() -> 個体LOD選択設定 {
    個体LOD選択設定::生成する(メートル::生成する(50.0), メートル::生成する(5.0)).unwrap()
}

/// ID列の`開始`から`件数`件。パス別の区間を切り出して期待する集合と突き合わせるために使う。
pub(super) fn 可視部分(選別係: &可視個体と段の選別係, 開始: usize, 件数: usize) -> Vec<u32> {
    選別係.id列()[開始..開始 + 件数].to_vec()
}
