//! 検査が選択を1回走らせるための呼び出し。受け取るのは視錐台と材料とアンカー、返すのは計数とID列である。
//! 段を1つだけ持つ群として走らせるのは、段が1つなら選択の結果が可視判定だけで決まり、可視判定の振る舞いが露わになるためである。

use blitz_math::{カメラ相対位置, メートル};
use blitz_render::cascade::帯数;

use crate::{
    個体LOD選択設定, 個体別段状態, 個体詳細段, 個体選択材料, 可視個体と段を選ぶ, 可視判定方式, 可視判定計数, 帯別可視判定, 段別ID受け皿, 段選択方式,
    群可視材料, 視錐台,
};

/// 段を1つだけ持つ群として選ぶ。段が1つなら選択の結果は可視判定だけで決まるため、この呼び出しは可視判定の振る舞いを露わにする。
/// 返すのは計数と、その群のID列のうちシーンパスの区間に置かれた個体の並びである。
pub(super) fn 単段で選ぶ(
    視錐台: &視錐台, 材料: &群可視材料, アンカー: カメラ相対位置
) -> (可視判定計数, Vec<u32>) {
    let mut 受け皿 = 段別ID受け皿::生成する();
    let 計数 = 単段で受け皿へ選ぶ(視錐台, 材料, アンカー, &mut 受け皿);
    (計数, 可視部分(&受け皿, 0, 計数.シーン可視数()))
}

/// 受け皿を呼び出し元が持つ形。複数の群を1本の列へ連ねる振る舞いを見る検査が使う。
/// 影の側をどの帯も全個体可視に固定するのは、この検査群が見るのがカメラ視錐台の振る舞いだけであり、
/// 帯ごとの判定が絡む振る舞いは`pass_interval`と`light_frustum`が別に見るためである。
pub(super) fn 単段で受け皿へ選ぶ(
    視錐台: &視錐台,
    材料: &群可視材料,
    アンカー: カメラ相対位置,
    受け皿: &mut 段別ID受け皿,
) -> 可視判定計数 {
    受け皿へ選ぶ(
        可視判定方式::視錐台で絞る(視錐台),
        帯別可視判定::全帯で全個体を可視とする,
        材料,
        アンカー,
        受け皿,
    )
}

/// シーンと帯ごとに別々の視錐台を与える形。パス別の区間の並びを見る検査が使う。
pub(super) fn 帯別で受け皿へ選ぶ(
    シーン視錐台: &視錐台,
    帯別視錐台: &[視錐台; 帯数],
    材料: &群可視材料,
    アンカー: カメラ相対位置,
    受け皿: &mut 段別ID受け皿,
) -> 可視判定計数 {
    受け皿へ選ぶ(
        可視判定方式::視錐台で絞る(シーン視錐台),
        帯別可視判定::帯ごとの視錐台で絞る(帯別視錐台),
        材料,
        アンカー,
        受け皿,
    )
}

pub(super) fn 受け皿へ選ぶ(
    シーン可視判定: 可視判定方式<'_>,
    帯別可視判定: 帯別可視判定<'_>,
    材料: &群可視材料,
    アンカー: カメラ相対位置,
    受け皿: &mut 段別ID受け皿,
) -> 可視判定計数 {
    let mut 状態 = 個体別段状態::生成する(材料.個体数(), 個体詳細段::最詳細());
    可視個体と段を選ぶ(
        &個体選択材料 {
            シーン可視判定,
            帯別可視判定,
            材料,
            カメラ相対アンカー: アンカー,
            段選択: 段選択方式::距離とヒステリシス(既定の段設定()),
        },
        &mut 状態,
        受け皿,
    )
}

pub(super) fn 既定の段設定() -> 個体LOD選択設定 {
    個体LOD選択設定::生成する(メートル::生成する(50.0), メートル::生成する(5.0)).unwrap()
}

/// ID列の`開始`から`件数`件。パス別の区間を切り出して期待する集合と突き合わせるために使う。
pub(super) fn 可視部分(受け皿: &段別ID受け皿, 開始: usize, 件数: usize) -> Vec<u32> {
    受け皿.id列()[開始..開始 + 件数].to_vec()
}
