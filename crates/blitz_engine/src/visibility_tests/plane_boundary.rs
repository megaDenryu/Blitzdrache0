//! 平面との境界での振る舞い。接する個体を描く側へ倒すこと、完全に外の個体だけを棄却すること、
//! 透視投影のカメラ後方が棄却されることを確かめる。

use super::fixture::{単位視錐台, 基準原点, 球, 球一覧から材料, 透視視錐台};
use super::run::単段で選ぶ;

#[test]
fn 境界球が平面へ接する個体は描く側へ倒す() {
    let 視錐台 = 単位視錐台();
    // 単位視錐台の右平面はx=1である。中心x=2・半径1の球はその平面へちょうど接する。
    let 材料 = 球一覧から材料(vec![球([2.0, 0.0, 0.5], 1.0)]);
    let (計数, 可視id一覧) = 単段で選ぶ(&視錐台, &材料, 基準原点(0.0, 0.0, 0.0));
    assert_eq!(計数.シーン可視数(), 1);
    assert_eq!(可視id一覧, vec![0]);
}

#[test]
fn 平面へ届かない個体だけを棄却する() {
    let 視錐台 = 単位視錐台();
    let 材料 = 球一覧から材料(vec![球([2.0, 0.0, 0.5], 0.5)]);
    let (計数, 可視id一覧) = 単段で選ぶ(&視錐台, &材料, 基準原点(0.0, 0.0, 0.0));
    assert_eq!(計数.シーン可視数(), 0);
    assert!(可視id一覧.is_empty());
}

#[test]
fn 透視投影ではカメラ後方の個体を棄却する() {
    let 視錐台 = 透視視錐台();
    let 材料 = 球一覧から材料(vec![球([0.0, 0.0, 10.0], 1.0)]);
    let (計数, _) = 単段で選ぶ(&視錐台, &材料, 基準原点(0.0, 0.0, 0.0));
    assert_eq!(計数.シーン可視数(), 0);
    assert_eq!(計数.候補数(), 1);
}

#[test]
fn 透視投影では前方の個体を可視にする() {
    let 視錐台 = 透視視錐台();
    let 材料 = 球一覧から材料(vec![球([0.0, 0.0, -10.0], 1.0)]);
    let (計数, _) = 単段で選ぶ(&視錐台, &材料, 基準原点(0.0, 0.0, 0.0));
    assert_eq!(計数.シーン可視数(), 1);
}

#[test]
fn 透視投影では遠クリップより遠い個体を棄却する() {
    let 視錐台 = 透視視錐台();
    let 材料 = 球一覧から材料(vec![球([0.0, 0.0, -500.0], 1.0)]);
    let (計数, _) = 単段で選ぶ(&視錐台, &材料, 基準原点(0.0, 0.0, 0.0));
    assert_eq!(計数.シーン可視数(), 0);
}
