//! シーンとシャドウを別々の視錐台で判定したときの4区分の並べ替え。
//! 4通りの区分がすべて現れる配置を1つ作り、ID列が全個体の並べ替えのままであること、
//! 2つのパスの範囲がそれぞれ期待するID集合と一致することを見る。

use super::fixture::{アンカー, ライト視錐台, 単位視錐台, 球, 球一覧から材料};
use super::run::両視錐台で受け皿へ選ぶ;
use crate::{可視判定方式, 可視判定計数, 段別ID受け皿, 群可視材料};

/// カメラの単位視錐台はx・yが-1から1、zが0から1を覆う。ライト視錐台は中心x=1の半幅1であるから、xが0から2を覆う。
/// 2つが重なるのはxが0から1の帯であり、この4点で4通りの区分がすべて現れる。
/// 個体の並びを区分の順と食い違わせるのは、並べ替えが恒等写像でも通る検査にしないためである。
/// 添字0は両方可視、1はどちらも不可視、2はシーンのみ可視、3はシャドウのみ可視になる。
fn 四区分の材料() -> 群可視材料 {
    let 中心x一覧 = [0.5, 5.0, -0.5, 1.5];
    球一覧から材料(中心x一覧.into_iter().map(|x| 球([x, 0.0, 0.5], 0.1)).collect())
}

fn 選ぶ(受け皿: &mut 段別ID受け皿) -> 可視判定計数 {
    let (カメラ, ライト) = (単位視錐台(), ライト視錐台(1.0));
    両視錐台で受け皿へ選ぶ(
        可視判定方式::視錐台で絞る(&カメラ),
        可視判定方式::視錐台で絞る(&ライト),
        &四区分の材料(),
        アンカー(0.0, 0.0, 0.0),
        受け皿,
    )
}

/// 並びは`[シーンのみ][両方][シャドウのみ][不可視]`であるから、ID列は2・0・3・1の順になる。
#[test]
fn 四区分が区分の順に並ぶ() {
    let mut 受け皿 = 段別ID受け皿::生成する();
    let 計数 = 選ぶ(&mut 受け皿);
    assert_eq!(受け皿.id列(), &[2, 0, 3, 1]);
    assert_eq!((計数.シーン可視数(), 計数.シャドウ可視数()), (2, 2));
    assert_eq!((計数.候補数(), 計数.個体判定数()), (4, 4));
}

#[test]
fn id列は全個体の並べ替えのままである() {
    let mut 受け皿 = 段別ID受け皿::生成する();
    選ぶ(&mut 受け皿);
    let mut 並び = 受け皿.id列().to_vec();
    並び.sort_unstable();
    assert_eq!(並び, vec![0, 1, 2, 3]);
}

#[test]
fn 各パスの範囲が期待するid集合と一致する() {
    let mut 受け皿 = 段別ID受け皿::生成する();
    選ぶ(&mut 受け皿);
    let 範囲 = 受け皿.段範囲列()[0];
    assert_eq!((範囲.開始(), 範囲.個体数()), (0, 4));
    assert_eq!(区間のid(&受け皿, 範囲.シーン().開始(), 範囲.シーン().描画数()), vec![2, 0]);
    assert_eq!(区間のid(&受け皿, 範囲.シャドウ().開始(), 範囲.シャドウ().描画数()), vec![0, 3]);
}

pub(super) fn 区間のid(受け皿: &段別ID受け皿, 開始: u32, 件数: u32) -> Vec<u32> {
    let 開始 = usize::try_from(開始).unwrap();
    let 件数 = usize::try_from(件数).unwrap();
    受け皿.id列()[開始..開始 + 件数].to_vec()
}
