//! 原型の境界球を個体の配置で写す計算の検査。平行移動が中心へ効くこと、
//! 軸ごとに違うスケールでは最大成分が半径へ掛かることを確かめる。

use super::fixture::単位球;
use crate::{個体境界球, 個体配置};

const 恒等回転: [f32; 4] = [0.0, 0.0, 0.0, 1.0];

#[test]
fn 平行移動が境界球の中心へ効く() {
    let 配置 = 個体配置::生成する([3.0, 4.0, 5.0], 恒等回転, [1.0; 3]).unwrap();
    let 球 = 個体境界球::配置で写す(単位球(), &配置);
    assert_eq!([球.中心().x().値(), 球.中心().y().値(), 球.中心().z().値()], [3.0, 4.0, 5.0]);
    assert_eq!(球.半径().値(), 1.0);
}

#[test]
fn 軸ごとに違うスケールでは最大成分が半径へ掛かる() {
    let 配置 = 個体配置::生成する([0.0; 3], 恒等回転, [0.5, 3.0, 2.0]).unwrap();
    let 球 = 個体境界球::配置で写す(単位球(), &配置);
    assert_eq!(球.半径().値(), 3.0);
}

#[test]
fn 負のスケールでも半径は絶対値で掛かる() {
    let 配置 = 個体配置::生成する([0.0; 3], 恒等回転, [-4.0, 1.0, 1.0]).unwrap();
    let 球 = 個体境界球::配置で写す(単位球(), &配置);
    assert_eq!(球.半径().値(), 4.0);
}
