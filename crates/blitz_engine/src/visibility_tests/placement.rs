//! 原型の境界球をアンカー基準の変換で写す計算の検査。平行移動が中心へ効くこと、
//! 軸ごとに違うスケールでは最も大きく伸びる軸が半径へ効くこと、回転だけでは半径が変わらないことを確かめる。

use blitz_math::{クォータニオン, メートル, ローカル, ワールド, 位置, 変換};

use super::fixture::単位球;
use crate::個体境界球;

fn 写す(平行移動: [f32; 3], 回転: [f32; 4], スケール: [f32; 3]) -> 個体境界球 {
    let 回転 = クォータニオン::<ローカル, ワールド>::生成する(回転[0], 回転[1], 回転[2], 回転[3]).unwrap();
    let 変換 = 変換::trsから生成する(
        位置::生成する(
            メートル::生成する(平行移動[0]),
            メートル::生成する(平行移動[1]),
            メートル::生成する(平行移動[2]),
        ),
        回転,
        スケール,
    );
    個体境界球::変換で写す(単位球(), 変換)
}

const 恒等回転: [f32; 4] = [0.0, 0.0, 0.0, 1.0];

#[test]
fn 平行移動が境界球の中心へ効く() {
    let 球 = 写す([3.0, 4.0, 5.0], 恒等回転, [1.0; 3]);
    assert_eq!([球.中心().x().値(), 球.中心().y().値(), 球.中心().z().値()], [3.0, 4.0, 5.0]);
    assert_eq!(球.半径().値(), 1.0);
}

#[test]
fn 軸ごとに違うスケールでは最大成分が半径へ掛かる() {
    let 球 = 写す([0.0; 3], 恒等回転, [0.5, 3.0, 2.0]);
    assert_eq!(球.半径().値(), 3.0);
}

#[test]
fn 負のスケールでも半径は絶対値で掛かる() {
    let 球 = 写す([0.0; 3], 恒等回転, [-4.0, 1.0, 1.0]);
    assert_eq!(球.半径().値(), 4.0);
}

#[test]
fn 回転を混ぜても半径はスケールだけで決まる() {
    // Y軸まわり45度の回転。回転は長さを変えないため、半径は一様スケールの2.0のままになる。
    let 半分 = std::f32::consts::FRAC_1_SQRT_2;
    let 球 = 写す([0.0; 3], [0.0, 半分, 0.0, 半分], [2.0; 3]);
    assert!((球.半径().値() - 2.0).abs() < 1.0e-5);
}
