//! シーンをカメラ視錐台、影を帯ごとの光空間直方体で判定したときのパス別区間の並び。
//! パスの正典順(シーン→帯0から帯3)に区間が並ぶこと、同じ個体IDが複数の帯の区間へ現れること、
//! 群の粗い判定で棄却した帯が個体の球判定を1回も行わないこと、各区間が期待するID集合と一致することを見る。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の帯別区間(4区分並べの後継)」

use blitz_render::cascade::帯番号;
use blitz_render::可視パス;

use super::fixture::{アンカー, 単位視錐台, 帯別ライト直方体, 球, 球一覧から材料};
use super::run::帯別で受け皿へ選ぶ;
use crate::{可視判定計数, 段別ID受け皿, 群可視材料};

/// カメラの単位視錐台はx・yが-1から1、zが0から1を覆う。帯の直方体は中心xの半幅1であるから、帯0と帯3はxが0から2、
/// 帯1はxが4から6、帯2はxが-4から-2を覆う。
/// 個体を4体置き、添字0(x=0.5)はカメラと帯0と帯3、添字1(x=5.0)は帯1だけ、添字2(x=-0.5)はカメラだけ、
/// 添字3(x=1.5)は帯0と帯3だけに入る。帯2はどの個体も含まないうえ、群の包囲領域そのものが範囲の外にある。
fn 四体の材料() -> 群可視材料 {
    let 中心x一覧 = [0.5, 5.0, -0.5, 1.5];
    球一覧から材料(中心x一覧.into_iter().map(|x| 球([x, 0.0, 0.5], 0.1)).collect())
}

fn 選ぶ(受け皿: &mut 段別ID受け皿) -> 可視判定計数 {
    let カメラ = 単位視錐台();
    let 帯別 = 帯別ライト直方体([1.0, 5.0, -3.0, 1.0]);
    帯別で受け皿へ選ぶ(&カメラ, &帯別, &四体の材料(), アンカー(0.0, 0.0, 0.0), 受け皿)
}

fn 区間のid(受け皿: &段別ID受け皿, パス: 可視パス) -> Vec<u32> {
    let 区間 = 受け皿.段範囲列()[0].パス(パス);
    let 開始 = usize::try_from(区間.開始()).unwrap();
    let 件数 = usize::try_from(区間.描画数()).unwrap();
    受け皿.id列()[開始..開始 + 件数].to_vec()
}

/// 列はシーン[0, 2]・帯0[0, 3]・帯1[1]・帯2[]・帯3[0, 3]を正典順に連ねた7件になる。
/// 個体の並びと区分の順が食い違うことを含む配置であり、並べ替えが恒等写像でも通る検査にはならない。
#[test]
fn パス別の区間が正典順に並ぶ() {
    let mut 受け皿 = 段別ID受け皿::生成する();
    選ぶ(&mut 受け皿);
    assert_eq!(受け皿.id列(), &[0, 2, 0, 3, 1, 0, 3]);
}

#[test]
fn 各パスの区間が期待するid集合と一致する() {
    let mut 受け皿 = 段別ID受け皿::生成する();
    選ぶ(&mut 受け皿);
    assert_eq!(区間のid(&受け皿, 可視パス::シーン), vec![0, 2]);
    assert_eq!(区間のid(&受け皿, 可視パス::影帯(帯番号::帯0)), vec![0, 3]);
    assert_eq!(区間のid(&受け皿, 可視パス::影帯(帯番号::帯1)), vec![1]);
    assert_eq!(区間のid(&受け皿, 可視パス::影帯(帯番号::帯2)), Vec::<u32>::new());
    assert_eq!(区間のid(&受け皿, 可視パス::影帯(帯番号::帯3)), vec![0, 3]);
}

/// 同じ個体IDが帯0と帯3の区間へ現れる。キャスターの重複所属は正しい影に必要であり、これを許すことが
/// 4区分並べを置き換えた理由そのものである。
#[test]
fn 同じ個体が複数の帯の区間へ現れる() {
    let mut 受け皿 = 段別ID受け皿::生成する();
    選ぶ(&mut 受け皿);
    let 帯0 = 区間のid(&受け皿, 可視パス::影帯(帯番号::帯0));
    let 帯3 = 区間のid(&受け皿, 可視パス::影帯(帯番号::帯3));
    assert!(帯0.contains(&0) && 帯3.contains(&0), "帯0{帯0:?}と帯3{帯3:?}の両方に個体0が要る");
}

/// 段の個体数は可視の有無によらず常にその段の全個体である。段別個体数の合計が個体数と一致することが、
/// どの段からも漏れた個体が無いことの根拠になる(検査はレンダラーの書き込み境界が持つ)。
#[test]
fn 段の個体数は全個体を数える() {
    let mut 受け皿 = 段別ID受け皿::生成する();
    選ぶ(&mut 受け皿);
    assert_eq!(受け皿.段範囲列()[0].個体数(), 4);
}

/// 帯別可視数は帯ごとに違う値になり、帯和集合可視数は複数の帯へ属する個体を1回だけ数える。
/// 帯2は群の粗い判定で棄却されるため0である。
#[test]
fn 帯別可視数と帯和集合可視数を別々に数える() {
    let mut 受け皿 = 段別ID受け皿::生成する();
    let 計数 = 選ぶ(&mut 受け皿);
    assert_eq!((計数.候補数(), 計数.個体判定数()), (4, 4));
    assert_eq!(計数.シーン可視数(), 2);
    assert_eq!(計数.帯別可視数(), [2, 1, 0, 2]);
    assert_eq!(計数.帯和集合可視数(), 3, "個体0・1・3が1つ以上の帯へ影を落とす");
}
