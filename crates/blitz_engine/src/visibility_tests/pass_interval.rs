//! シーンをカメラ視錐台、影を距離区分ごとの光空間直方体で判定したときのパス別区間の並び。
//! パスの正典順(シーン→距離区分0から距離区分3)に区間が並ぶこと、同じ個体IDが複数の距離区分の区間へ現れること、
//! 群の粗い判定で棄却した距離区分が個体の球判定を1回も行わないこと、各区間が期待するID集合と一致することを見る。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」

use blitz_render::cascade::距離区分番号;
use blitz_render::可視パス;

use super::fixture::{単位視錐台, 基準原点, 球, 球一覧から材料, 距離区分別のライト直方体};
use super::run::距離区分別で受け皿へ選ぶ;
use crate::{可視判定計数, 段別ID受け皿, 群可視材料};

/// カメラの単位視錐台はx・yが-1から1、zが0から1を覆う。距離区分の直方体は中心xの半幅1であるから、距離区分0と距離区分3はxが0から2、
/// 距離区分1はxが4から6、距離区分2はxが-4から-2を覆う。
/// 個体を4体置き、添字0(x=0.5)はカメラと距離区分0と距離区分3、添字1(x=5.0)は距離区分1だけ、添字2(x=-0.5)はカメラだけ、
/// 添字3(x=1.5)は距離区分0と距離区分3だけに入る。距離区分2はどの個体も含まないうえ、群の包囲領域そのものが範囲の外にある。
fn 四体の材料() -> 群可視材料 {
    let 中心x一覧 = [0.5, 5.0, -0.5, 1.5];
    球一覧から材料(中心x一覧.into_iter().map(|x| 球([x, 0.0, 0.5], 0.1)).collect())
}

fn 選ぶ(受け皿: &mut 段別ID受け皿) -> 可視判定計数 {
    let カメラ = 単位視錐台();
    let 距離区分別 = 距離区分別のライト直方体([1.0, 5.0, -3.0, 1.0]);
    距離区分別で受け皿へ選ぶ(&カメラ, &距離区分別, &四体の材料(), 基準原点(0.0, 0.0, 0.0), 受け皿)
}

fn 区間のid(受け皿: &段別ID受け皿, パス: 可視パス) -> Vec<u32> {
    let 区間 = 受け皿.段範囲列()[0].パス(パス);
    let 開始 = usize::try_from(区間.開始()).unwrap();
    let 件数 = usize::try_from(区間.描画数()).unwrap();
    受け皿.id列()[開始..開始 + 件数].to_vec()
}

/// 列はシーン[0, 2]・距離区分0[0, 3]・距離区分1[1]・距離区分2[]・距離区分3[0, 3]を正典順に連ねた7件になる。
/// 個体の並びと区分の順が食い違うことを含む配置であり、並べ替えが恒等写像でも通る検査にはならない。
#[test]
fn パス別の区間が正典順に並ぶ() {
    let mut 受け皿 = 段別ID受け皿::生成する();
    選ぶ(&mut 受け皿);
    assert_eq!(受け皿.id列(), &[0, 2, 0, 3, 1, 0, 3]);
}

#[test]
fn 各パスの区間が期待するid集合と一致する() {
    let mut 受け皿 = 段別ID受け皿::生成する();
    選ぶ(&mut 受け皿);
    assert_eq!(区間のid(&受け皿, 可視パス::シーン), vec![0, 2]);
    assert_eq!(区間のid(&受け皿, 可視パス::影の距離区分(距離区分番号::距離区分0)), vec![0, 3]);
    assert_eq!(区間のid(&受け皿, 可視パス::影の距離区分(距離区分番号::距離区分1)), vec![1]);
    assert_eq!(区間のid(&受け皿, 可視パス::影の距離区分(距離区分番号::距離区分2)), Vec::<u32>::new());
    assert_eq!(区間のid(&受け皿, 可視パス::影の距離区分(距離区分番号::距離区分3)), vec![0, 3]);
}

/// 同じ個体IDが距離区分0と距離区分3の区間へ現れる。キャスターの重複所属は正しい影に必要であり、これを許すことが
/// 4区分並べを置き換えた理由そのものである。
#[test]
fn 同じ個体が複数の距離区分の区間へ現れる() {
    let mut 受け皿 = 段別ID受け皿::生成する();
    選ぶ(&mut 受け皿);
    let 距離区分0 = 区間のid(&受け皿, 可視パス::影の距離区分(距離区分番号::距離区分0));
    let 距離区分3 = 区間のid(&受け皿, 可視パス::影の距離区分(距離区分番号::距離区分3));
    assert!(
        距離区分0.contains(&0) && 距離区分3.contains(&0),
        "距離区分0{距離区分0:?}と距離区分3{距離区分3:?}の両方に個体0が要る"
    );
}

/// 段の個体数は可視の有無によらず常にその段の全個体である。段別個体数の合計が個体数と一致することが、
/// どの段からも漏れた個体が無いことの根拠になる(検査はレンダラーの書き込み境界が持つ)。
#[test]
fn 段の個体数は全個体を数える() {
    let mut 受け皿 = 段別ID受け皿::生成する();
    選ぶ(&mut 受け皿);
    assert_eq!(受け皿.段範囲列()[0].個体数(), 4);
}

/// 距離区分別の可視数は距離区分ごとに違う値になり、距離区分の和集合の可視数は複数の距離区分へ属する個体を1回だけ数える。
/// 距離区分2は群の粗い判定で棄却されるため0である。
#[test]
fn 距離区分別の可視数と距離区分の和集合の可視数を別々に数える() {
    let mut 受け皿 = 段別ID受け皿::生成する();
    let 計数 = 選ぶ(&mut 受け皿);
    assert_eq!((計数.候補数(), 計数.個体判定数()), (4, 4));
    assert_eq!(計数.シーン可視数(), 2);
    assert_eq!(計数.距離区分別の可視数(), [2, 1, 0, 2]);
    assert_eq!(計数.距離区分の和集合の可視数(), 3, "個体0・1・3が1つ以上の距離区分へ影を落とす");
}
