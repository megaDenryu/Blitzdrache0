//! 2段階判定の振る舞い。粗い判定で群ごと棄却したとき個体の判定が1回も走らないこと、
//! 平面をまたぐ群で個体別に内外が分かれること、カメラ相対アンカーが判定を動かすこと、
//! 受け皿へ追記して既存の内容を消さないことを確かめる。

use super::fixture::{アンカー, 単位視錐台, 材料, 球, 球一覧から材料};
use crate::可視個体を選ぶ;

#[test]
fn 完全に外の群は個体を1件も判定しない() {
    let 視錐台 = 単位視錐台();
    let 材料 = 球一覧から材料(vec![球([100.0, 0.0, 0.5], 1.0), 球([102.0, 0.0, 0.5], 1.0)]);
    let mut 受け皿 = Vec::new();
    let 計数 = 可視個体を選ぶ(&視錐台, &材料, アンカー(0.0, 0.0, 0.0), &mut 受け皿);
    assert_eq!(計数.候補数(), 2);
    assert_eq!(計数.個体判定数(), 0);
    assert_eq!(計数.可視数(), 0);
    assert!(受け皿.is_empty());
}

#[test]
fn 平面をまたぐ群は個体別に内外が分かれる() {
    let 視錐台 = 単位視錐台();
    let 材料 = 球一覧から材料(vec![球([0.0, 0.0, 0.5], 0.25), 球([5.0, 0.0, 0.5], 0.25), 球([0.5, 0.0, 0.5], 0.25)]);
    let mut 受け皿 = Vec::new();
    let 計数 = 可視個体を選ぶ(&視錐台, &材料, アンカー(0.0, 0.0, 0.0), &mut 受け皿);
    assert_eq!(計数.候補数(), 3);
    assert_eq!(計数.個体判定数(), 3);
    assert_eq!(受け皿, vec![0, 2]);
}

#[test]
fn カメラ相対アンカーが個体の内外を動かす() {
    let 視錐台 = 単位視錐台();
    let 球一覧 = vec![球([0.0, 0.0, 0.5], 0.25)];
    let 材料 = 材料([-0.25, -0.25, 0.25], [0.25, 0.25, 0.75], 球一覧);
    let mut 内側 = Vec::new();
    assert_eq!(可視個体を選ぶ(&視錐台, &材料, アンカー(0.0, 0.0, 0.0), &mut 内側).可視数(), 1);
    let mut 外側 = Vec::new();
    let 計数 = 可視個体を選ぶ(&視錐台, &材料, アンカー(10.0, 0.0, 0.0), &mut 外側);
    assert_eq!(計数.可視数(), 0);
    assert_eq!(計数.個体判定数(), 0);
}

#[test]
fn 受け皿へ追記し既存の内容を消さない() {
    let 視錐台 = 単位視錐台();
    let 材料 = 球一覧から材料(vec![球([0.0, 0.0, 0.5], 0.25)]);
    let mut 受け皿 = vec![7, 8];
    可視個体を選ぶ(&視錐台, &材料, アンカー(0.0, 0.0, 0.0), &mut 受け皿);
    assert_eq!(受け皿, vec![7, 8, 0]);
}

#[test]
fn 計数は群をまたいで足し合わせられる() {
    let 視錐台 = 単位視錐台();
    let 近い群 = 球一覧から材料(vec![球([0.0, 0.0, 0.5], 0.25)]);
    let 遠い群 = 球一覧から材料(vec![球([50.0, 0.0, 0.5], 0.25), 球([52.0, 0.0, 0.5], 0.25)]);
    let mut 受け皿 = Vec::new();
    let 計数 = 可視個体を選ぶ(&視錐台, &近い群, アンカー(0.0, 0.0, 0.0), &mut 受け皿).足す(可視個体を選ぶ(
        &視錐台,
        &遠い群,
        アンカー(0.0, 0.0, 0.0),
        &mut 受け皿,
    ));
    assert_eq!(計数.候補数(), 3);
    assert_eq!(計数.個体判定数(), 1);
    assert_eq!(計数.可視数(), 1);
}
