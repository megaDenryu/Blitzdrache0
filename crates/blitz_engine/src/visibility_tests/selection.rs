//! 2段階判定の振る舞い。粗い判定で群ごと棄却したとき個体の判定が1回も走らないこと、
//! 平面をまたぐ群で個体別に内外が分かれること、カメラ相対アンカーが判定を動かすこと、
//! 複数の群を1本のID列へ連ねることを確かめる。
//!
//! 粗い判定で棄却しても、シャドウパスが描く個体の段を決めるためにID列そのものは全個体ぶん積まれる。
//! 省かれるのは個体ごとの視錐台判定であり、そのことは個体判定数が0になることで示される。

use super::fixture::{アンカー, 単位視錐台, 材料, 球, 球一覧から材料};
use super::run::{単段で受け皿へ選ぶ, 単段で選ぶ, 可視部分};
use crate::段別ID受け皿;

#[test]
fn 完全に外の群は個体を1件も判定しない() {
    let 視錐台 = 単位視錐台();
    let 材料 = 球一覧から材料(vec![球([100.0, 0.0, 0.5], 1.0), 球([102.0, 0.0, 0.5], 1.0)]);
    let (計数, 可視id一覧) = 単段で選ぶ(&視錐台, &材料, アンカー(0.0, 0.0, 0.0));
    assert_eq!(計数.候補数(), 2);
    assert_eq!(計数.個体判定数(), 0);
    assert_eq!(計数.可視数(), 0);
    assert!(可視id一覧.is_empty());
}

/// 粗い判定で棄却した群でも、ID列には全個体が並ぶ。シャドウパスがその全個体を描くためである。
#[test]
fn 完全に外の群でもid列には全個体が並ぶ() {
    let 視錐台 = 単位視錐台();
    let 材料 = 球一覧から材料(vec![球([100.0, 0.0, 0.5], 1.0), 球([102.0, 0.0, 0.5], 1.0)]);
    let mut 受け皿 = 段別ID受け皿::生成する();
    単段で受け皿へ選ぶ(&視錐台, &材料, アンカー(0.0, 0.0, 0.0), &mut 受け皿);
    assert_eq!(受け皿.id列().len(), 2);
    assert_eq!(受け皿.段範囲列().len(), 1);
}

#[test]
fn 平面をまたぐ群は個体別に内外が分かれる() {
    let 視錐台 = 単位視錐台();
    let 材料 = 球一覧から材料(vec![球([0.0, 0.0, 0.5], 0.25), 球([5.0, 0.0, 0.5], 0.25), 球([0.5, 0.0, 0.5], 0.25)]);
    let (計数, 可視id一覧) = 単段で選ぶ(&視錐台, &材料, アンカー(0.0, 0.0, 0.0));
    assert_eq!(計数.候補数(), 3);
    assert_eq!(計数.個体判定数(), 3);
    assert_eq!(可視id一覧, vec![0, 2]);
}

/// 可視個体は段の範囲の先頭側へ寄り、不可視個体はその後ろへ続く。合計は常に個体数である。
#[test]
fn 不可視個体は可視個体の後ろへ並ぶ() {
    let 視錐台 = 単位視錐台();
    let 材料 = 球一覧から材料(vec![球([0.0, 0.0, 0.5], 0.25), 球([5.0, 0.0, 0.5], 0.25), 球([0.5, 0.0, 0.5], 0.25)]);
    let mut 受け皿 = 段別ID受け皿::生成する();
    単段で受け皿へ選ぶ(&視錐台, &材料, アンカー(0.0, 0.0, 0.0), &mut 受け皿);
    assert_eq!(受け皿.id列(), &[0, 2, 1]);
    let 範囲 = 受け皿.段範囲列()[0];
    assert_eq!((範囲.開始(), 範囲.可視数(), 範囲.個体数()), (0, 2, 3));
}

#[test]
fn カメラ相対アンカーが個体の内外を動かす() {
    let 視錐台 = 単位視錐台();
    let 球一覧 = vec![球([0.0, 0.0, 0.5], 0.25)];
    let 材料 = 材料([-0.25, -0.25, 0.25], [0.25, 0.25, 0.75], 球一覧);
    assert_eq!(単段で選ぶ(&視錐台, &材料, アンカー(0.0, 0.0, 0.0)).0.可視数(), 1);
    let (計数, _) = 単段で選ぶ(&視錐台, &材料, アンカー(10.0, 0.0, 0.0));
    assert_eq!(計数.可視数(), 0);
    assert_eq!(計数.個体判定数(), 0);
}

/// 2つ目の群のID列は1つ目の後ろへ連なり、段の範囲の開始はその群のID列の先頭からの相対位置になる。
#[test]
fn 複数の群を1本のid列へ連ねる() {
    let 視錐台 = 単位視錐台();
    let 一つ目 = 球一覧から材料(vec![球([0.0, 0.0, 0.5], 0.25), 球([5.0, 0.0, 0.5], 0.25)]);
    let 二つ目 = 球一覧から材料(vec![球([0.5, 0.0, 0.5], 0.25)]);
    let mut 受け皿 = 段別ID受け皿::生成する();
    単段で受け皿へ選ぶ(&視錐台, &一つ目, アンカー(0.0, 0.0, 0.0), &mut 受け皿);
    let 二つ目の開始 = 受け皿.id列の長さ();
    let 計数 = 単段で受け皿へ選ぶ(&視錐台, &二つ目, アンカー(0.0, 0.0, 0.0), &mut 受け皿);
    assert_eq!(受け皿.id列().len(), 3);
    assert_eq!(可視部分(&受け皿, 二つ目の開始, 計数.可視数()), vec![0]);
    assert_eq!(受け皿.段範囲列()[1].開始(), 0, "段の範囲は群ごとのID列の先頭からの相対位置である");
}
