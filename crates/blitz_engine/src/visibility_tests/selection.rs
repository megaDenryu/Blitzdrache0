//! 2段階判定の振る舞い。粗い判定で群ごと棄却したとき個体の判定が1回も走らないこと、
//! 平面をまたぐ群で個体別に内外が分かれること、カメラ相対の基準原点が判定を動かすこと、
//! 複数の群を1本のID列へ連ねることを確かめる。
//!
//! この検査群は影の側をどの距離区分も全個体可視に固定するため、シーンの粗い判定で棄却した群でも距離区分の区間には全個体が並ぶ。
//! 省かれるのは個体ごとの視錐台判定であり、そのことは個体判定数が0になることで示される。

use blitz_render::cascade::{距離区分数, 距離区分番号};
use blitz_render::可視パス;

use super::fixture::{単位視錐台, 基準原点, 材料, 球, 球一覧から材料};
use super::run::{単段で受け皿へ選ぶ, 単段で選ぶ, 可視部分};
use crate::段別ID受け皿;

#[test]
fn 完全に外の群は個体を1件も判定しない() {
    let 視錐台 = 単位視錐台();
    let 材料 = 球一覧から材料(vec![球([100.0, 0.0, 0.5], 1.0), 球([102.0, 0.0, 0.5], 1.0)]);
    let (計数, 可視id一覧) = 単段で選ぶ(&視錐台, &材料, 基準原点(0.0, 0.0, 0.0));
    assert_eq!(計数.候補数(), 2);
    assert_eq!(計数.個体判定数(), 0);
    assert_eq!(計数.シーン可視数(), 0);
    assert!(可視id一覧.is_empty());
}

/// シーンの粗い判定で棄却した群でも、段の個体数は全個体を数え、影の区間には全個体が並ぶ。
/// この検査は影をどの距離区分も全個体可視に固定しているため、列は距離区分数ぶんの区間に全個体を持つ。
#[test]
fn 完全に外の群でも段の個体数は全個体を数える() {
    let 視錐台 = 単位視錐台();
    let 材料 = 球一覧から材料(vec![球([100.0, 0.0, 0.5], 1.0), 球([102.0, 0.0, 0.5], 1.0)]);
    let mut 受け皿 = 段別ID受け皿::生成する();
    単段で受け皿へ選ぶ(&視錐台, &材料, 基準原点(0.0, 0.0, 0.0), &mut 受け皿);
    assert_eq!(受け皿.段範囲列().len(), 1);
    assert_eq!(受け皿.段範囲列()[0].個体数(), 2);
    assert_eq!(
        受け皿.id列().len(),
        2 * 距離区分数,
        "シーンの区間は空になり、距離区分ごとの区間に2件ずつ並ぶ"
    );
}

#[test]
fn 平面をまたぐ群は個体別に内外が分かれる() {
    let 視錐台 = 単位視錐台();
    let 材料 = 球一覧から材料(vec![球([0.0, 0.0, 0.5], 0.25), 球([5.0, 0.0, 0.5], 0.25), 球([0.5, 0.0, 0.5], 0.25)]);
    let (計数, 可視id一覧) = 単段で選ぶ(&視錐台, &材料, 基準原点(0.0, 0.0, 0.0));
    assert_eq!(計数.候補数(), 3);
    assert_eq!(計数.個体判定数(), 3);
    assert_eq!(可視id一覧, vec![0, 2]);
}

/// シーンの区間には可視個体だけが並び、シーンから外れた個体はその区間に現れない。
/// この検査の影の側は全個体可視であるため、続く距離区分0の区間には全個体が並ぶ。
#[test]
fn シーンの区間には可視個体だけが並ぶ() {
    let 視錐台 = 単位視錐台();
    let 材料 = 球一覧から材料(vec![球([0.0, 0.0, 0.5], 0.25), 球([5.0, 0.0, 0.5], 0.25), 球([0.5, 0.0, 0.5], 0.25)]);
    let mut 受け皿 = 段別ID受け皿::生成する();
    単段で受け皿へ選ぶ(&視錐台, &材料, 基準原点(0.0, 0.0, 0.0), &mut 受け皿);
    let 範囲 = 受け皿.段範囲列()[0];
    assert_eq!(範囲.個体数(), 3);
    let シーン = 範囲.パス(可視パス::シーン);
    assert_eq!((シーン.開始(), シーン.描画数()), (0, 2));
    assert_eq!(&受け皿.id列()[0..2], &[0, 2]);
    let 距離区分0 = 範囲.パス(可視パス::影の距離区分(距離区分番号::距離区分0));
    assert_eq!((距離区分0.開始(), 距離区分0.描画数()), (2, 3));
    assert_eq!(&受け皿.id列()[2..5], &[0, 1, 2]);
}

#[test]
fn カメラ相対の基準原点が個体の内外を動かす() {
    let 視錐台 = 単位視錐台();
    let 球一覧 = vec![球([0.0, 0.0, 0.5], 0.25)];
    let 材料 = 材料([-0.25, -0.25, 0.25], [0.25, 0.25, 0.75], 球一覧);
    assert_eq!(単段で選ぶ(&視錐台, &材料, 基準原点(0.0, 0.0, 0.0)).0.シーン可視数(), 1);
    let (計数, _) = 単段で選ぶ(&視錐台, &材料, 基準原点(10.0, 0.0, 0.0));
    assert_eq!(計数.シーン可視数(), 0);
    assert_eq!(計数.個体判定数(), 0);
}

/// 2つ目の群のID列は1つ目の後ろへ連なり、区間の開始はその群のID列の先頭からの相対位置になる。
#[test]
fn 複数の群を1本のid列へ連ねる() {
    let 視錐台 = 単位視錐台();
    let 一つ目 = 球一覧から材料(vec![球([0.0, 0.0, 0.5], 0.25), 球([5.0, 0.0, 0.5], 0.25)]);
    let 二つ目 = 球一覧から材料(vec![球([0.5, 0.0, 0.5], 0.25)]);
    let mut 受け皿 = 段別ID受け皿::生成する();
    単段で受け皿へ選ぶ(&視錐台, &一つ目, 基準原点(0.0, 0.0, 0.0), &mut 受け皿);
    let 二つ目の開始 = 受け皿.id列の長さ();
    assert_eq!(二つ目の開始, 1 + 2 * 距離区分数, "1つ目はシーン1件と距離区分ごとに2件を並べる");
    let 計数 = 単段で受け皿へ選ぶ(&視錐台, &二つ目, 基準原点(0.0, 0.0, 0.0), &mut 受け皿);
    assert_eq!(可視部分(&受け皿, 二つ目の開始, 計数.シーン可視数()), vec![0]);
    assert_eq!(
        受け皿.段範囲列()[1].パス(可視パス::シーン).開始(),
        0,
        "区間の開始は群ごとのID列の先頭からの相対位置である"
    );
}
