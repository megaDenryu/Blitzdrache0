//! 距離区分の判定における境界球の半径の効き。区間の境目が半径ぶん外へ広がること、正射影の半幅が軸ごとに違っても
//! 半径がメートルのまま効くことを見る。
//! 半径をメートルで効かせられるのは判定を光空間で行うためであり、クリップ空間で判定すると軸ごとに半幅で
//! 割った座標になって半径を軸ごとに割り直す必要が出る。非等方の検査はその割り直しの漏れを捕まえる。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」

use blitz_render::cascade::{距離区分数, 距離区分番号};
use blitz_render::可視パス;

use super::fixture::{
    全距離区分同じ非等方ライト直方体, 単位視錐台, 基準原点, 球, 球一覧から材料, 距離区分別のライト直方体
};
use super::run::距離区分別で選別係へ選ぶ;
use crate::{可視個体と段の選別係, 可視判定計数, 群可視材料, 距離区分別の光空間直方体};

fn 選ぶ(
    直方体: &距離区分別の光空間直方体, 材料: &群可視材料, 選別係: &mut 可視個体と段の選別係
) -> 可視判定計数 {
    距離区分別で選別係へ選ぶ(&単位視錐台(), 直方体, 材料, 基準原点(0.0, 0.0, 0.0), 選別係)
}

fn 距離区分0の区間のid(選別係: &可視個体と段の選別係) -> Vec<u32> {
    let 区間 = 選別係.段範囲列()[0].パス(可視パス::影の距離区分(距離区分番号::距離区分0));
    let 開始 = usize::try_from(区間.開始()).unwrap();
    let 件数 = usize::try_from(区間.描画数()).unwrap();
    選別係.id列()[開始..開始 + 件数].to_vec()
}

/// 中心が側面の外にあり、半径ぶんが範囲へ届く個体。半幅1の直方体に対して中心x=1.05・半径0.1であるから、
/// 中心は0.05メートル外にあり半径が届く。接する個体は描く側へ倒す。
#[test]
fn 半径が側面へ届く個体は距離区分へ入る() {
    let 材料 = 球一覧から材料(vec![球([0.0, 0.0, 0.5], 0.1), 球([1.05, 0.0, 0.5], 0.1)]);
    let mut 選別係 = 可視個体と段の選別係::生成する();
    let 計数 = 選ぶ(&距離区分別のライト直方体([0.0; 距離区分数]), &材料, &mut 選別係);
    assert_eq!(計数.距離区分別の可視数(), [2; 距離区分数]);
    assert_eq!(距離区分0の区間のid(&選別係), vec![0, 1]);
}

/// 中心が0.2メートル外にあり半径0.1が届かない個体。群の包囲領域は範囲へ重なるため個体の判定は走り、
/// この個体だけが落ちる。
#[test]
fn 半径が側面へ届かない個体は距離区分へ入らない() {
    let 材料 = 球一覧から材料(vec![球([0.0, 0.0, 0.5], 0.1), 球([1.2, 0.0, 0.5], 0.1)]);
    let mut 選別係 = 可視個体と段の選別係::生成する();
    let 計数 = 選ぶ(&距離区分別のライト直方体([0.0; 距離区分数]), &材料, &mut 選別係);
    assert_eq!(計数.個体判定数(), 2, "群は粗い判定を通る");
    assert_eq!(計数.距離区分別の可視数(), [1; 距離区分数]);
    assert_eq!(距離区分0の区間のid(&選別係), vec![0]);
}

/// 横半幅1・縦半幅8の非等方な正射影。xへ0.05メートル出た個体とyへ0.05メートル出た個体は半径0.1で入り、
/// yへ0.3メートル出た個体は同じ半径では入らない。この検査は新実装がメートルの光空間で半径を判定する
/// 性質を固定する。正規化を忘れてクリップ座標のまま半径を比べる仮想の実装があれば、yは半幅8で割られて
/// 0.3メートルが0.0375になり、半径0.1と比べて内と誤る。この対照のためにyへ0.3メートル出た個体を混ぜている。
#[test]
fn 非等方な正射影でも半径は軸によらず効く() {
    let 材料 = 球一覧から材料(vec![球([1.05, 0.0, 0.5], 0.1), 球([0.0, 8.05, 0.5], 0.1), 球([0.0, 8.3, 0.5], 0.1)]);
    let mut 選別係 = 可視個体と段の選別係::生成する();
    let 計数 = 選ぶ(&全距離区分同じ非等方ライト直方体(1.0, 8.0), &材料, &mut 選別係);
    assert_eq!(計数.距離区分別の可視数(), [2; 距離区分数]);
    assert_eq!(距離区分0の区間のid(&選別係), vec![0, 1]);
}
