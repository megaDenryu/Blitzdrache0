//! スキン行列: 姿勢とスキンからGPU境界向けの列優先行列一覧を計算する(判断43・44)。

use blitz_math::{ローカル, 変換};

use crate::asset::スキンデータ;

use super::pose::姿勢;

/// GPU境界向けの列優先f32配列(4x4)の列挙。
#[derive(Debug, Clone, PartialEq)]
pub struct スキン行列一覧 {
    内部: Vec<[[f32; 4]; 4]>,
}

impl スキン行列一覧 {
    fn 生成する(内部: Vec<[[f32; 4]; 4]>) -> Self {
        Self { 内部 }
    }

    pub fn 関節数(&self) -> usize {
        self.内部.len()
    }

    pub fn 列優先配列一覧(&self) -> &[[[f32; 4]; 4]] {
        &self.内部
    }
}

/// ローカル行列合成→親子階層の乗算(トポロジカル順の1パス)→逆バインド行列の順で計算する。
///
/// 不変条件: `スキン`と`姿勢`は同じスキンに由来し、関節数が一致する。
/// 一致しない呼び出しはこの関数の契約違反(プログラムのバグ)としてpanicする。
pub fn スキン行列を計算する(スキン: &スキンデータ, 姿勢: &姿勢) -> スキン行列一覧 {
    assert_eq!(
        スキン.ジョイント一覧.len(),
        姿勢.関節数(),
        "スキンのジョイント数と姿勢の関節数が一致しない(不変条件違反)"
    );

    let mut グローバル一覧: Vec<変換<ローカル, ローカル>> = Vec::with_capacity(スキン.ジョイント一覧.len());
    for (添字, ジョイント) in スキン.ジョイント一覧.iter().enumerate() {
        let ローカル行列 = 姿勢.関節(添字).へ変換する();
        let グローバル行列 = match ジョイント.親添字 {
            Some(親) => ローカル行列.合成する(グローバル一覧[親]),
            None => ローカル行列,
        };
        グローバル一覧.push(グローバル行列);
    }

    let 列優先配列一覧 = スキン
        .ジョイント一覧
        .iter()
        .zip(グローバル一覧)
        .map(|(ジョイント, グローバル行列)| ジョイント.逆バインド行列.合成する(グローバル行列).gpu境界用列優先配列())
        .collect();

    スキン行列一覧::生成する(列優先配列一覧)
}
