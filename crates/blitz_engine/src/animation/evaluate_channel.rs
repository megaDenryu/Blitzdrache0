//! 1チャンネルぶんのキー間補間評価。ステップ補間は手前の値、線形補間は
//! 平行移動/スケールがlerp、回転がslerp(判断43)。

use blitz_math::{クォータニオン, ローカル, 秒};

use crate::asset::{チャンネル, 補間種別};

use super::keyframe_interpolation::{区間を求める, 区間};

pub(super) fn vec3を評価する(チャンネル: &チャンネル<[f32; 3]>, 時刻: 秒) -> [f32; 3] {
    match 区間を求める(&チャンネル.時刻列, 時刻) {
        区間::単一 { 添字 } => チャンネル.値列[添字],
        区間::二点間 {
            前添字,
            後添字,
            係数,
        } => match チャンネル.補間 {
            補間種別::ステップ => チャンネル.値列[前添字],
            補間種別::線形 => 線形補間する(チャンネル.値列[前添字], チャンネル.値列[後添字], 係数),
        },
    }
}

pub(super) fn 回転を評価する(
    チャンネル: &チャンネル<[f32; 4]>,
    時刻: 秒,
) -> クォータニオン<ローカル, ローカル> {
    match 区間を求める(&チャンネル.時刻列, 時刻) {
        区間::単一 { 添字 } => 生の成分から変換する(チャンネル.値列[添字]),
        区間::二点間 {
            前添字,
            後添字,
            係数,
        } => match チャンネル.補間 {
            補間種別::ステップ => 生の成分から変換する(チャンネル.値列[前添字]),
            補間種別::線形 => {
                let 前 = 生の成分から変換する(チャンネル.値列[前添字]);
                let 後 = 生の成分から変換する(チャンネル.値列[後添字]);
                前.slerp(&後, 係数)
            }
        },
    }
}

fn 線形補間する(前: [f32; 3], 後: [f32; 3], 係数: f32) -> [f32; 3] {
    std::array::from_fn(|軸| 前[軸] + (後[軸] - 前[軸]) * 係数)
}

pub(super) fn 生の成分から変換する(値: [f32; 4]) -> クォータニオン<ローカル, ローカル> {
    // 注意: 姿勢を評価するはResultを返さない契約(判断43)のため、ロード時に本来
    // 弾かれるべき異常なゼロ長回転が万一残っていた場合は恒等回転へ縮退させる。
    クォータニオン::生成する(値[0], 値[1], 値[2], 値[3]).unwrap_or_else(|_| クォータニオン::恒等())
}
