//! ブレンドするの単体テスト(判断43): 係数0/1が単独クリップ評価と一致すること。

use blitz_math::秒;

use crate::asset::{アニメーションクリップ, ジョイントアニメーションチャンネル, チャンネル, 補間種別};

use super::blend::ブレンドする;
use super::evaluate::姿勢を評価する;
use super::test_support::恒等スキンを作る;

fn 定数平行移動クリップを作る(x: f32) -> アニメーションクリップ {
    let チャンネル = チャンネル {
        時刻列: vec![秒::生成する(0.0)],
        値列: vec![[x, 0.0, 0.0]],
        補間: 補間種別::ステップ,
    };
    アニメーションクリップ {
        名前: "テスト".to_string(),
        継続秒: 秒::生成する(1.0),
        ジョイントチャンネル一覧: vec![ジョイントアニメーションチャンネル {
            平行移動: Some(チャンネル),
            回転: None,
            スケール: None,
        }],
    }
}

#[test]
fn 係数0と1は単独クリップ評価と一致する() {
    let クリップa = 定数平行移動クリップを作る(1.0);
    let クリップb = 定数平行移動クリップを作る(5.0);
    let スキン = 恒等スキンを作る(1);
    let 姿勢a = 姿勢を評価する(&クリップa, &スキン, 秒::生成する(0.0));
    let 姿勢b = 姿勢を評価する(&クリップb, &スキン, 秒::生成する(0.0));

    assert_eq!(ブレンドする(&姿勢a, &姿勢b, 0.0), 姿勢a);
    assert_eq!(ブレンドする(&姿勢a, &姿勢b, 1.0), 姿勢b);
}

#[test]
fn 係数0_5は中間値になる() {
    let クリップa = 定数平行移動クリップを作る(0.0);
    let クリップb = 定数平行移動クリップを作る(10.0);
    let スキン = 恒等スキンを作る(1);
    let 姿勢a = 姿勢を評価する(&クリップa, &スキン, 秒::生成する(0.0));
    let 姿勢b = 姿勢を評価する(&クリップb, &スキン, 秒::生成する(0.0));

    let 混合姿勢 = ブレンドする(&姿勢a, &姿勢b, 0.5);
    assert_eq!(混合姿勢.関節(0).平行移動().x().値(), 5.0);
}
