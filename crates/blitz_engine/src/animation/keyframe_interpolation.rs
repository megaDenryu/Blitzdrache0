//! キーフレーム列上で問い合わせ時刻を挟む区間を求める。時刻列は昇順が前提(判断42)。

use blitz_math::秒;

pub(super) enum 区間 {
    単一 { 添字: usize },
    二点間 { 前添字: usize, 後添字: usize, 係数: f32 },
}

/// 問い合わせ時刻が範囲外なら端の値を単一で返す(クランプ)。
/// 時刻列が空の場合は呼び出し元の値列も空である不変条件のもと`単一{添字:0}`を返す
/// (値列の読み出しは呼び出し元が空チェックを行う)。
pub(super) fn 区間を求める(時刻列: &[秒], 問い合わせ時刻: 秒) -> 区間 {
    let Some(&最初) = 時刻列.first() else {
        return 区間::単一 { 添字: 0 };
    };
    if 問い合わせ時刻 <= 最初 {
        return 区間::単一 { 添字: 0 };
    }

    let 最終添字 = 時刻列.len() - 1;
    if 問い合わせ時刻 >= 時刻列[最終添字] {
        return 区間::単一 { 添字: 最終添字 };
    }

    for 前添字 in 0..最終添字 {
        let 後添字 = 前添字 + 1;
        if 問い合わせ時刻 >= 時刻列[前添字] && 問い合わせ時刻 <= 時刻列[後添字] {
            let 区間長 = (時刻列[後添字] - 時刻列[前添字]).値();
            let 係数 = if 区間長 > 0.0 {
                (問い合わせ時刻 - 時刻列[前添字]).値() / 区間長
            } else {
                0.0
            };
            return 区間::二点間 {
                前添字,
                後添字,
                係数,
            };
        }
    }
    // 不変条件: 時刻列が昇順である限りここには到達しない。
    区間::単一 { 添字: 最終添字 }
}
