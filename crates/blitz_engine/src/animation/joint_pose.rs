//! 関節TRS: 1ジョイントぶんのローカル姿勢(平行移動・回転・スケール)。

use blitz_math::{クォータニオン, メートル, ローカル, 位置, 変換};

/// ローカル(親ジョイント基準)のTRS。`へ変換する`で`変換<ローカル, ローカル>`へ合成する。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 関節TRS {
    平行移動: 位置<ローカル>,
    回転: クォータニオン<ローカル, ローカル>,
    スケール: [f32; 3],
}

impl 関節TRS {
    pub fn 生成する(平行移動: 位置<ローカル>, 回転: クォータニオン<ローカル, ローカル>, スケール: [f32; 3]) -> Self {
        Self {
            平行移動,
            回転,
            スケール,
        }
    }

    /// チャンネル未指定のジョイントが持つ恒等姿勢(判断43)。
    pub fn 恒等() -> Self {
        Self {
            平行移動: 位置::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0)),
            回転: クォータニオン::恒等(),
            スケール: [1.0, 1.0, 1.0],
        }
    }

    pub fn 平行移動(&self) -> 位置<ローカル> {
        self.平行移動
    }

    pub fn 回転(&self) -> クォータニオン<ローカル, ローカル> {
        self.回転
    }

    pub fn スケール(&self) -> [f32; 3] {
        self.スケール
    }

    /// TRSを`変換<ローカル, ローカル>`へ合成する。
    pub fn へ変換する(&self) -> 変換<ローカル, ローカル> {
        変換::trsから生成する(self.平行移動, self.回転, self.スケール)
    }
}
