//! クリップとスキンから姿勢を評価する(判断43・49)。

use blitz_math::{メートル, ローカル, 位置, 秒};

use crate::asset::{アニメーションクリップ, ジョイントアニメーションチャンネル, スキンデータ, 静的TRS};

use super::evaluate_channel::{vec3を評価する, 回転を評価する, 生の成分から変換する};
use super::joint_pose::関節TRS;
use super::pose::姿勢;

/// 時刻は継続秒でループ(剰余)する。チャンネル未指定の成分は該当ジョイントの
/// バインド時ローカル姿勢(静的TRS)を既定値とする(判断49: glTF仕様どおり。恒等ではない)。
///
/// 不変条件: `クリップ`と`スキン`は同じ骨格に由来し、ジョイント数が一致する。
/// 一致しない呼び出しはこの関数の契約違反(プログラムのバグ)としてpanicする。
pub fn 姿勢を評価する(クリップ: &アニメーションクリップ, スキン: &スキンデータ, 時刻: 秒) -> 姿勢 {
    assert_eq!(
        クリップ.ジョイントチャンネル一覧.len(),
        スキン.ジョイント一覧.len(),
        "クリップとスキンのジョイント数が一致しない(不変条件違反)"
    );

    let ループ時刻 = 時刻をループさせる(時刻, クリップ.継続秒);
    let 関節姿勢一覧 = クリップ
        .ジョイントチャンネル一覧
        .iter()
        .zip(&スキン.ジョイント一覧)
        .map(|(チャンネル, ジョイント)| 関節姿勢を評価する(チャンネル, &ジョイント.バインド時, ループ時刻))
        .collect();
    姿勢::生成する(関節姿勢一覧)
}

fn 関節姿勢を評価する(
    チャンネル: &ジョイントアニメーションチャンネル, バインド時: &静的TRS, 時刻: 秒
) -> 関節TRS {
    let 平行移動 = チャンネル.平行移動.as_ref().map_or(バインド時.平行移動, |c| vec3を評価する(c, 時刻));
    let 回転 = チャンネル
        .回転
        .as_ref()
        .map_or_else(|| 生の成分から変換する(バインド時.回転), |c| 回転を評価する(c, 時刻));
    let スケール = チャンネル.スケール.as_ref().map_or(バインド時.スケール, |c| vec3を評価する(c, 時刻));

    関節TRS::生成する(位置化する(平行移動), 回転, スケール)
}

fn 位置化する(値: [f32; 3]) -> 位置<ローカル> {
    位置::生成する(メートル::生成する(値[0]), メートル::生成する(値[1]), メートル::生成する(値[2]))
}

fn 時刻をループさせる(時刻: 秒, 継続秒: 秒) -> 秒 {
    let 継続 = 継続秒.値();
    if 継続 <= 0.0 {
        return 秒::生成する(0.0);
    }
    秒::生成する(時刻.値().rem_euclid(継続))
}
