//! 2つの姿勢を混ぜる割合と、その割合が受け取れない値だったこと。
//!
//! 裸の`f32`で受け取らないのは、この層を流れる単精度の量が割合・時刻(秒)・スケールの3つあり、姿勢を混ぜる口へ
//! 秒やスケールを渡しても署名が通るためである。0から1の割合を1から100の百分率と取り違えても計算は成立し、
//! 姿勢が黙って片方のクリップへ張り付く。

use thiserror::Error;

#[derive(Debug, Error)]
pub enum 姿勢のブレンド係数エラー {
    #[error("姿勢のブレンド係数が0から1の範囲でない: {実測}")]
    範囲の外 { 実測: f32 },
}

/// 2つ目の姿勢が混ざる割合。0で1つ目だけ、1で2つ目だけになる。
/// 不変条件: 0以上1以下である(非有限はこの範囲に入らないため同時に拒まれる)。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 姿勢のブレンド係数(f32);

impl 姿勢のブレンド係数 {
    pub fn 生成する(値: f32) -> Result<Self, 姿勢のブレンド係数エラー> {
        if !(0.0..=1.0).contains(&値) {
            return Err(姿勢のブレンド係数エラー::範囲の外 { 実測: 値 });
        }
        Ok(Self(値))
    }

    /// 補間の式が使う生値。混ぜる計算の内側だけが通る。
    pub(super) fn 値(self) -> f32 {
        self.0
    }
}
