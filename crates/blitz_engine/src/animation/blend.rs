//! 2つの姿勢をTRS段階で補間する(判断43: 行列を直接補間しない)。

use super::joint_pose::関節TRS;
use super::pose::姿勢;

/// `係数`0で`姿勢a`、1で`姿勢bと一致する。回転はslerp、平行移動・スケールはlerp。
///
/// 不変条件: `姿勢a`と`姿勢b`は同じスキンから評価されたもので、関節数が一致する。
/// 一致しない呼び出しはこの関数の契約違反(プログラムのバグ)としてpanicする。
pub fn ブレンドする(姿勢a: &姿勢, 姿勢b: &姿勢, 係数: f32) -> 姿勢 {
    assert_eq!(姿勢a.関節数(), 姿勢b.関節数(), "ブレンドする姿勢の関節数が一致しない(不変条件違反)");

    let 関節姿勢一覧 = (0..姿勢a.関節数())
        .map(|添字| 関節姿勢をブレンドする(姿勢a.関節(添字), 姿勢b.関節(添字), 係数))
        .collect();
    姿勢::生成する(関節姿勢一覧)
}

fn 関節姿勢をブレンドする(a: &関節TRS, b: &関節TRS, 係数: f32) -> 関節TRS {
    let 平行移動a = a.平行移動();
    let 平行移動b = b.平行移動();
    let 平行移動 = blitz_math::位置::生成する(
        平行移動a.x() + (平行移動b.x() - 平行移動a.x()) * 係数,
        平行移動a.y() + (平行移動b.y() - 平行移動a.y()) * 係数,
        平行移動a.z() + (平行移動b.z() - 平行移動a.z()) * 係数,
    );
    let 回転 = a.回転().slerp(&b.回転(), 係数);
    let スケールa = a.スケール();
    let スケールb = b.スケール();
    let スケール = std::array::from_fn(|軸| スケールa[軸] + (スケールb[軸] - スケールa[軸]) * 係数);

    関節TRS::生成する(平行移動, 回転, スケール)
}
