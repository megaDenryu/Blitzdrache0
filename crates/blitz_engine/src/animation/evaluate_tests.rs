//! 姿勢を評価するの単体テスト(判断43): キー間補間・ステップ補間・ループ折り返し。
//! バインド時TRSの既定適用は`evaluate_bind_pose_tests`(判断49)を参照。

use blitz_math::秒;

use crate::asset::{アニメーションクリップ, ジョイントアニメーションチャンネル, チャンネル, 補間種別};

use super::evaluate::姿勢を評価する;
use super::test_support::恒等スキンを作る;

fn 平行移動クリップを作る(補間: 補間種別) -> アニメーションクリップ {
    let チャンネル = チャンネル {
        時刻列: vec![秒::生成する(0.0), 秒::生成する(1.0)],
        値列: vec![[0.0, 0.0, 0.0], [2.0, 0.0, 0.0]],
        補間,
    };
    let ジョイント = ジョイントアニメーションチャンネル {
        平行移動: Some(チャンネル),
        回転: None,
        スケール: None,
    };
    アニメーションクリップ {
        名前: "テスト".to_string(),
        継続秒: 秒::生成する(1.0),
        ジョイントチャンネル一覧: vec![ジョイント],
    }
}

#[test]
fn 線形補間はキー間の中間値になる() {
    let クリップ = 平行移動クリップを作る(補間種別::線形);
    let スキン = 恒等スキンを作る(1);
    let 姿勢 = 姿勢を評価する(&クリップ, &スキン, 秒::生成する(0.5));
    assert_eq!(姿勢.関節(0).平行移動().x().値(), 1.0);
}

#[test]
fn ステップ補間は手前の値を保持する() {
    let クリップ = 平行移動クリップを作る(補間種別::ステップ);
    let スキン = 恒等スキンを作る(1);
    let 姿勢 = 姿勢を評価する(&クリップ, &スキン, 秒::生成する(0.5));
    assert_eq!(姿勢.関節(0).平行移動().x().値(), 0.0);
}

#[test]
fn 継続秒を超えた時刻はループする() {
    let クリップ = 平行移動クリップを作る(補間種別::線形);
    let スキン = 恒等スキンを作る(1);
    let 折り返し前 = 姿勢を評価する(&クリップ, &スキン, 秒::生成する(0.5));
    let 折り返し後 = 姿勢を評価する(&クリップ, &スキン, 秒::生成する(1.5));
    assert_eq!(折り返し前.関節(0).平行移動(), 折り返し後.関節(0).平行移動());
}
