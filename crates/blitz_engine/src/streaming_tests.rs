use blitz_math::{大域メートル, 大域ワールド位置};

use crate::{チャンク格子, チャンク格子エラー};

#[test]
fn 負座標はゼロ方向でなく負方向へ床を取る() {
    let 格子 = 格子を作る(100.0);
    let Ok(集合) = 格子.必要集合を計算する(位置(-0.1, -100.1), 0) else {
        panic!("負座標の必要集合を計算できなかった");
    };
    assert_eq!((集合[0].座標().x(), 集合[0].座標().z()), (-1, -2));
}

#[test]
fn 必要集合は中心から外周へ決定的に並ぶ() {
    let 格子 = 格子を作る(64.0);
    let Ok(一回目) = 格子.必要集合を計算する(位置(65.0, 129.0), 2) else {
        panic!("必要集合を計算できなかった");
    };
    let Ok(二回目) = 格子.必要集合を計算する(位置(65.0, 129.0), 2) else {
        panic!("必要集合を再計算できなかった");
    };
    assert_eq!(一回目, 二回目);
    assert_eq!(一回目.len(), 25);
    assert_eq!((一回目[0].座標().x(), 一回目[0].座標().z()), (1, 2));
    assert_eq!(一回目.iter().filter(|要求| 要求.優先距離() == 1).count(), 8);
    assert_eq!(一回目.iter().filter(|要求| 要求.優先距離() == 2).count(), 16);
}

#[test]
fn 異なる座標は負値を含めて異なる番号になる() {
    let 格子 = 格子を作る(1.0);
    let Ok(集合) = 格子.必要集合を計算する(位置(-0.1, -0.1), 1) else {
        panic!("番号試験用の必要集合を計算できなかった");
    };
    let mut 番号一覧: Vec<_> = 集合.iter().map(|要求| 要求.座標().番号を返す()).collect();
    番号一覧.sort_unstable();
    番号一覧.dedup();
    assert_eq!(番号一覧.len(), 9);
}

#[test]
fn 不正寸法と非有限位置を型付きエラーにする() {
    assert!(matches!(
        チャンク格子::生成する(大域メートル::生成する(0.0)),
        Err(チャンク格子エラー::一辺不正)
    ));
    let 格子 = 格子を作る(1.0);
    assert!(matches!(
        格子.必要集合を計算する(位置(f64::NAN, 0.0), 0),
        Err(チャンク格子エラー::位置非有限)
    ));
}

#[test]
fn i32両端のチャンク座標を正確に変換する() {
    let 格子 = 格子を作る(1.0);
    let Ok(最小) = 格子.必要集合を計算する(位置(f64::from(i32::MIN), 0.0), 0) else {
        panic!("最小チャンク座標を計算できなかった");
    };
    let Ok(最大) = 格子.必要集合を計算する(位置(f64::from(i32::MAX), 0.0), 0) else {
        panic!("最大チャンク座標を計算できなかった");
    };
    assert_eq!(最小[0].座標().x(), i32::MIN);
    assert_eq!(最大[0].座標().x(), i32::MAX);
    assert!(matches!(
        格子.必要集合を計算する(位置(f64::from(i32::MAX), 0.0), 1),
        Err(チャンク格子エラー::座標範囲外)
    ));
}

fn 格子を作る(一辺: f64) -> チャンク格子 {
    match チャンク格子::生成する(大域メートル::生成する(一辺)) {
        Ok(格子) => 格子,
        Err(誤り) => panic!("試験用格子を生成できなかった: {誤り}"),
    }
}

fn 位置(x: f64, z: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(x), 大域メートル::生成する(0.0), 大域メートル::生成する(z))
}
