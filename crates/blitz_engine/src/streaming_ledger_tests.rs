use blitz_math::{大域メートル, 大域ワールド位置};

use crate::{GPU転送完了結果, チャンク台帳, チャンク格子, チャンク状態, 準備完了結果};

#[test]
fn 読込からgpu完了後の解除まで順に遷移する() {
    let 必要集合 = 必要集合を作る(0.0, 0);
    let id = 必要集合[0].id();
    let mut 台帳 = チャンク台帳::空を作る();
    let Ok(初回差分) = 台帳.必要集合を反映する(&必要集合) else {
        panic!("初回必要集合を反映できなかった");
    };
    assert_eq!(初回差分.読込要求一覧(), 必要集合);
    assert_eq!(台帳.状態を引く(id), Some(チャンク状態::読込待ち));
    assert_eq!(台帳.読込を開始する(id), Ok(()));
    assert_eq!(台帳.準備完了を反映する(id), Ok(準備完了結果::GPU転送待ち));
    assert_eq!(台帳.状態を引く(id), Some(チャンク状態::準備済み));
    assert_eq!(台帳.gpu転送を開始する(id), Ok(()));
    assert_eq!(台帳.gpu転送完了を反映する(id), Ok(GPU転送完了結果::フレーム反映待ち));
    assert_eq!(台帳.フレーム境界で常駐化する(id), Ok(()));
    let Ok(解除差分) = 台帳.必要集合を反映する(&[]) else {
        panic!("空の必要集合を反映できなかった");
    };
    assert_eq!(解除差分.解除要求一覧(), [id]);
    assert_eq!(台帳.状態を引く(id), Some(チャンク状態::解除待ち));
    assert_eq!(台帳.gpu使用完了後に解除する(id), Ok(()));
    assert_eq!(台帳.登録数(), 0);
}

#[test]
fn 読込要求は必要集合の中心優先順を保つ() {
    let 必要集合 = 必要集合を作る(0.0, 1);
    let mut 台帳 = チャンク台帳::空を作る();
    let Ok(差分) = 台帳.必要集合を反映する(&必要集合) else {
        panic!("必要集合を台帳へ反映できなかった");
    };
    assert_eq!(差分.読込要求一覧(), 必要集合);
    assert_eq!(差分.読込要求一覧()[0].優先距離(), 0);
    assert_eq!(差分.読込要求一覧().len(), 9);
}

pub(super) fn 必要集合を作る(x: f64, 半径: u8) -> Vec<crate::チャンク要求> {
    let 格子 = match チャンク格子::生成する(大域メートル::生成する(100.0)) {
        Ok(格子) => 格子,
        Err(誤り) => panic!("試験用格子を作れなかった: {誤り}"),
    };
    let 位置 = 大域ワールド位置::生成する(大域メートル::生成する(x), 大域メートル::生成する(0.0), 大域メートル::生成する(0.0));
    match 格子.必要集合を計算する(位置, 半径) {
        Ok(集合) => 集合,
        Err(誤り) => panic!("試験用必要集合を作れなかった: {誤り}"),
    }
}
