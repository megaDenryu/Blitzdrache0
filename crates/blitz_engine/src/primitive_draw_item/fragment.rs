//! 静的描画片: フレームによって変わらない描画発行の識別。原型・詳細段・プリミティブ添字・材質スロットIDの4つで1つを指す。
//! 原型を束の中での描画対象添字で表すのは、現行のシーン表現では1つの描画対象が1つの原型を持ち、両者が1対1に対応するためである。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「可視ID列の契約」

use crate::asset::材質スロットID;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 静的描画片 {
    描画対象添字: usize,
    詳細段番号: usize,
    プリミティブ添字: usize,
    材質スロット: 材質スロットID,
}

impl 静的描画片 {
    /// `描画対象添字`は束の中での並び順であり、可視個体選択が描画対象を引くときの添字と同じ値である。
    /// `プリミティブ添字`はその詳細段のメッシュが持つプリミティブ列の中での位置である。詳細段ごとにプリミティブ数が違ってよいため、段をまたいで同じ添字が同じ材質を指すとは限らない。
    pub fn 生成する(
        描画対象添字: usize, 詳細段番号: usize, プリミティブ添字: usize, 材質スロット: 材質スロットID
    ) -> Self {
        Self {
            描画対象添字,
            詳細段番号,
            プリミティブ添字,
            材質スロット,
        }
    }

    pub fn 描画対象添字(self) -> usize {
        self.描画対象添字
    }

    pub fn 詳細段番号(self) -> usize {
        self.詳細段番号
    }

    pub fn プリミティブ添字(self) -> usize {
        self.プリミティブ添字
    }

    pub fn 材質スロット(self) -> 材質スロットID {
        self.材質スロット
    }
}
