//! プリミティブ描画項目一覧: 1つの束が持つ全描画対象のプリミティブ描画項目を、描画対象の並び順に連ねた器。
//! 束の読込時に一度だけ組み立て、束の解除まで同じ器を読み続ける。中身が静的だからである。
//! 可視個体区間は参照だけを持ち、実際の区間は毎フレームの可視選別が別に持つため、フレームごとに束を作り直す理由が無い。
//! シーンの差し替えで同じ器へ入れ直すときは`空にする`が確保済みの容量を残すため、束の入れ替えでもヒープの再確保が起きない。

use super::item::プリミティブ描画項目;

#[derive(Debug, Default)]
pub struct プリミティブ描画項目一覧 {
    一覧: Vec<プリミティブ描画項目>,
}

impl プリミティブ描画項目一覧 {
    pub fn 生成する() -> Self {
        Self::default()
    }

    pub fn 空にする(&mut self) {
        self.一覧.clear();
    }

    pub fn 積む(&mut self, 束: プリミティブ描画項目) {
        self.一覧.push(束);
    }

    pub fn 一覧(&self) -> &[プリミティブ描画項目] {
        &self.一覧
    }

    pub fn 件数(&self) -> usize {
        self.一覧.len()
    }

    /// `開始`以降のプリミティブ描画項目。範囲外の開始には空の並びを返す。1つの描画対象ぶんを、組み立ての前後で数えた件数から切り出すのに使う。
    pub fn 開始以降を参照する(&self, 開始: usize) -> &[プリミティブ描画項目] {
        self.一覧.get(開始..).unwrap_or_default()
    }
}
