//! 描画対象1つぶんのプリミティブ描画項目を組み立てる工程。プリミティブ描画項目一覧が受け取るのは形状と材質集合と束の中での描画対象添字、積むのは詳細段ごと・プリミティブごとのプリミティブ描画項目である。
//! 全詳細段の全プリミティブを1件ずつ展開するのは、段ごとにプリミティブ数が違ってよい契約のためである。1段だけを見て他の段の材質を決めることはできない。
//! 可視個体区間の参照は描画対象添字だけから作り、その描画対象の全プリミティブ描画項目へ同じ値を配る。可視選別を個体・原型・詳細段について1回だけ行う契約がこれである。
//!
//! インデックス区間と頂点基準はここで値へ写す。形状と材質集合は描画発行より前に破棄されるため、添字とスロットIDだけを残すと解決先が消える。
//! 材質は値を写さず、スロットIDが材質集合に実在することだけを確かめる。材質のCPU側データはレンダラーがGPUへ載せるまでの寿命であり、
//! ここで複製するとテクスチャ画素が束の寿命ぶん居座る。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「可視ID列の契約」

use crate::asset::{描画形状, 材質集合};

use super::draw_range::プリミティブ描画範囲;
use super::error::プリミティブ描画項目エラー;
use super::fragment::静的描画片;
use super::item::プリミティブ描画項目;
use super::list::プリミティブ描画項目一覧;
use super::visible_interval::可視個体区間参照;

impl プリミティブ描画項目一覧 {
    /// 描画対象1つぶんを展開して自分の末尾へ連ねる。失敗したときは途中まで積んだぶんが残るため、
    /// 呼び出し元は失敗を伝播して束ごと捨てる。
    pub fn 描画対象1つぶんを積む(
        &mut self,
        形状: &描画形状,
        材質集合: &材質集合,
        描画対象添字: usize,
    ) -> Result<(), プリミティブ描画項目エラー> {
        let 可視個体区間 = 可視個体区間参照::生成する(描画対象添字);
        for (詳細段番号, メッシュ) in 形状.全メッシュ().iter().enumerate() {
            if メッシュ.プリミティブ列.is_empty() {
                return Err(プリミティブ描画項目エラー::プリミティブ列が空 { 詳細段番号 });
            }
            for (プリミティブ添字, プリミティブ) in メッシュ.プリミティブ列.iter().enumerate() {
                if 材質集合.材質を参照する(プリミティブ.材質スロット).is_none() {
                    return Err(プリミティブ描画項目エラー::材質スロット未定義 {
                        番号: プリミティブ.材質スロット.番号を返す(),
                    });
                }
                let 描画片 = 静的描画片::生成する(描画対象添字, 詳細段番号, プリミティブ添字, プリミティブ.材質スロット);
                let 描画範囲 =
                    プリミティブ描画範囲::生成する(プリミティブ.インデックス開始, プリミティブ.インデックス数, プリミティブ.頂点基準);
                self.積む(プリミティブ描画項目::生成する(描画片, 描画範囲, 可視個体区間));
            }
        }
        Ok(())
    }
}
