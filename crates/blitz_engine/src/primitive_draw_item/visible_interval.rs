//! 可視個体区間参照: 1つのプリミティブ描画項目が読む可視個体区間を、束の中の描画対象で指す。
//! 区間の中身を持たないのは、可視選別が個体・原型・詳細段について1回だけ行われ、同じ原型の全プリミティブがその1つの結果を共有するためである。
//! プリミティブごとに区間を複製すると、可視ID列と距離区分別の計数が材質都合でプリミティブ数倍に膨らむ。
//! 束IDを含めないのは、この参照が有効なのは同じプリミティブ描画項目の中だけであり、束IDは束そのものが持つからである。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「可視ID列の契約」

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 可視個体区間参照 {
    描画対象添字: usize,
}

impl 可視個体区間参照 {
    pub fn 生成する(描画対象添字: usize) -> Self {
        Self { 描画対象添字 }
    }

    pub fn 描画対象添字(self) -> usize {
        self.描画対象添字
    }
}
