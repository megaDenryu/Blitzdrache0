//! プリミティブ描画項目: 静的な描画片へ、そのプリミティブが描くインデックス区間と、その片が読む可視個体区間の参照を結んだ描画発行の単位。
//!
//! 描画片は識別であり、区間と材質束縛が解決である。識別だけを持って解決を後回しにすると、解決に要るメッシュデータと材質集合が
//! 描画発行の時点で既に破棄されているため、どこからも辿れない。材質束縛は描画片が持つ2つの値から導けるため、値を重ねて持たない。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「可視ID列の契約」

use super::draw_range::プリミティブ描画範囲;
use super::fragment::静的描画片;
use super::material_binding::材質束縛参照;
use super::visible_interval::可視個体区間参照;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct プリミティブ描画項目 {
    描画片: 静的描画片,
    描画範囲: プリミティブ描画範囲,
    可視個体区間: 可視個体区間参照,
}

impl プリミティブ描画項目 {
    pub fn 生成する(
        描画片: 静的描画片, 描画範囲: プリミティブ描画範囲, 可視個体区間: 可視個体区間参照
    ) -> Self {
        Self {
            描画片,
            描画範囲,
            可視個体区間,
        }
    }

    pub fn 描画片(self) -> 静的描画片 {
        self.描画片
    }

    pub fn 描画範囲(self) -> プリミティブ描画範囲 {
        self.描画範囲
    }

    /// この項目が塗る材質を指す参照。描画片が持つ描画対象添字と材質スロットIDから導く。
    pub fn 材質束縛(self) -> 材質束縛参照 {
        材質束縛参照::生成する(self.描画片.描画対象添字(), self.描画片.材質スロット())
    }

    pub fn 可視個体区間(self) -> 可視個体区間参照 {
        self.可視個体区間
    }
}
