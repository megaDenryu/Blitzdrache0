//! 材質束縛参照: 1つの描画項目が塗る材質を、破棄されない語彙だけで指す参照。束の中での描画対象添字と、その原型が持つ材質スロットIDの組である。
//!
//! 材質集合の中の割当添字を持たないのは、材質集合がシーンデータとともに破棄され、添字の指す先が消えるためである。材質スロットIDは原型が所有する語彙であり、
//! 集合が消えても意味を保つ。
//! 束の描画項目はテクスチャの画素を複製して持たず、この参照だけを持つ。
//! 解決先はレンダラーが描画対象ごとに持つ材質スロット番号から大域材質IDへの対応であり、その材質IDをフレームが束縛する
//! 資源表世代へ解決してGPUのレコード添字が決まる。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「束縛バックエンドの移行境界」

use crate::asset::材質スロットID;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 材質束縛参照 {
    描画対象添字: usize,
    材質スロット: 材質スロットID,
}

impl 材質束縛参照 {
    pub fn 生成する(描画対象添字: usize, 材質スロット: 材質スロットID) -> Self {
        Self {
            描画対象添字, 材質スロット
        }
    }

    pub fn 描画対象添字(self) -> usize {
        self.描画対象添字
    }

    pub fn 材質スロット(self) -> 材質スロットID {
        self.材質スロット
    }
}
