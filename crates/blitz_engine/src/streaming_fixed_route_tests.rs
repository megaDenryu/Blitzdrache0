use blitz_math::{大域メートル, 大域ワールド位置};

use crate::{固定経路, 固定経路エラー};

#[test]
fn 同じフレーム番号からは同じ位置を返す() {
    let 経路 = 経路を作る(-150.0, 250.0, 5.0);
    for フレーム番号 in [0, 1, 37, 160, 4321] {
        assert_eq!(経路.位置を求める(フレーム番号), 経路.位置を求める(フレーム番号));
    }
}

#[test]
fn 終点で折り返して始点まで戻る() {
    let 経路 = 経路を作る(-150.0, 250.0, 5.0);
    // 全長400メートルを毎フレーム5メートル進むため、80フレームで終点、160フレームで始点へ戻る。
    assert!((経路.位置を求める(0).x().値() - (-150.0)).abs() < 1e-9);
    assert!((経路.位置を求める(80).x().値() - 250.0).abs() < 1e-9);
    assert!((経路.位置を求める(120).x().値() - 50.0).abs() < 1e-9);
    assert!((経路.位置を求める(160).x().値() - (-150.0)).abs() < 1e-9);
}

#[test]
fn 往復周期をまたいでも位置が一致する() {
    let 経路 = 経路を作る(-150.0, 250.0, 5.0);
    assert_eq!(経路.位置を求める(37), 経路.位置を求める(37 + 160));
    assert_eq!(経路.位置を求める(37), 経路.位置を求める(37 + 160 * 100));
}

#[test]
fn 経路外の軸は始点の値を保つ() {
    let 経路 = 経路を作る(-150.0, 250.0, 5.0);
    let 位置 = 経路.位置を求める(43);
    assert!((位置.y().値()).abs() < 1e-9);
    assert!((位置.z().値()).abs() < 1e-9);
}

#[test]
fn 端点が同じなら向きを決められないため拒否する() {
    let 端点 = 位置(0.0);
    assert_eq!(
        固定経路::生成する(端点, 端点, 大域メートル::生成する(5.0)).err(),
        Some(固定経路エラー::端点一致)
    );
}

#[test]
fn 移動量が正でなければ拒否する() {
    for 移動量 in [0.0, -5.0, f64::NAN] {
        assert_eq!(
            固定経路::生成する(位置(-150.0), 位置(250.0), 大域メートル::生成する(移動量)).err(),
            Some(固定経路エラー::移動量不正)
        );
    }
}

#[test]
fn 端点が非有限なら拒否する() {
    assert_eq!(
        固定経路::生成する(位置(f64::INFINITY), 位置(250.0), 大域メートル::生成する(5.0)).err(),
        Some(固定経路エラー::端点非有限)
    );
}

fn 経路を作る(始点x: f64, 終点x: f64, 移動量: f64) -> 固定経路 {
    match 固定経路::生成する(位置(始点x), 位置(終点x), 大域メートル::生成する(移動量)) {
        Ok(経路) => 経路,
        Err(誤り) => panic!("試験用の固定経路を作れなかった: {誤り}"),
    }
}

fn 位置(x: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(x), 大域メートル::生成する(0.0), 大域メートル::生成する(0.0))
}
