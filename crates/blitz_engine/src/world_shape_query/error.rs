//! 地形と建物の両方への問い合わせで破れる条件。
//!
//! 「読み込まれていないチャンクを覆いが含む」も「高さ場の広がりの外へ出た」もここに入らない。それは値が
//! 壊れたのではなく、どこまでを調べられたかの話であり、`問い合わせ完全性`が別の軸で表す。
//!
//! 高さ場を持たない世界もここに入らない。地形が1つも無い世界は、地形に当たらないという確定した答えを持つ。

use blitz_collision::height_field::{カプセルの掃引の問い合わせエラー, 線分の問い合わせエラー};
use blitz_collision::oriented_box::直方体の問い合わせエラー;
use blitz_collision::shape::{カプセルの生成エラー, 形の局所座標の生成エラー};
use blitz_math::方向エラー;

use crate::static_shape::index::静的世界の候補の選別エラー;

/// 地形と建物の両方への問い合わせが拒否する理由。
#[derive(Debug, Clone, Copy, PartialEq, thiserror::Error)]
pub enum 世界の形への問い合わせエラー {
    /// 地形の高さ場に対する線分の問い合わせが値を作れなかった。
    #[error("地形への線分の問い合わせが失敗した: {0}")]
    地形の線分を評価できない(#[from] 線分の問い合わせエラー),
    /// 地形の高さ場に対するカプセルの掃引の問い合わせが値を作れなかった。
    #[error("地形へのカプセルの掃引の問い合わせが失敗した: {0}")]
    地形の掃引を評価できない(#[from] カプセルの掃引の問い合わせエラー),
    /// 覆いに触れうる子形状の候補を挙げられなかった。
    #[error("静的世界の候補を選別できない: {0}")]
    候補を選別できない(#[from] 静的世界の候補の選別エラー),
    /// 掃引するカプセルを、半径がその条件を満たさないために作れなかった。
    #[error("掃引するカプセルを作れない: {0}")]
    掃引するカプセルを作れない(#[from] カプセルの生成エラー),
    /// 問い合わせの点や向きを、候補のチャンクの区画を基準にした形の局所座標へ写せなかった。
    #[error("問い合わせをチャンクの局所座標へ写せない: {0}")]
    問い合わせを局所座標へ写せない(#[from] 形の局所座標の生成エラー),
    /// 候補に挙がった直方体への詳細判定が値を作れなかった。
    #[error("建物の直方体への詳細判定が失敗した: {0}")]
    建物の形を評価できない(#[from] 直方体の問い合わせエラー),
    /// 直方体が返した局所座標の単位法線を、世界の座標の単位方向として作れなかった。
    #[error("建物への接触の単位法線を世界の向きへ写せない: {0}")]
    接触の単位法線を世界へ写せない(#[from] 方向エラー),
}
