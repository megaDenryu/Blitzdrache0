//! 世界の形への問い合わせ: 地形の高さ場と読込済みチャンクの静的物理形状の両方を相手にする操作サービス。
//! 高さ場の読み口と静的世界の候補の選別をコンストラクタで受け取って保持するため、問い合わせの署名に
//! 高さ場も形状の保管もチャンクの刻みも現れない。
//!
//! 候補の受け皿を呼び出し側から受け取るのは、1回の問い合わせで確保を起こさないためである。受け皿を使い回せば、
//! 2回目以降の問い合わせは確保を1つもしない。受け皿は入口の側で空にされ、型付きエラーで返るときも空である。
//! 契約は`静的世界の候補の選別`と同じである。

use crate::height_field::高さ場の読み口;
use crate::static_shape::index::静的世界の候補の選別;

/// 地形の高さ場と読込済みチャンクの静的物理形状の両方を相手に、最初の当たりを答える操作サービス。
pub struct 世界の形への問い合わせ<'世界> {
    高さ場の読み口: &'世界 高さ場の読み口,
    候補の選別: 静的世界の候補の選別<'世界>,
}

impl<'世界> 世界の形への問い合わせ<'世界> {
    /// 高さ場の読み口と、読込済みチャンクの形状を相手にする候補の選別を受け取って作る。
    pub fn 生成する(高さ場の読み口: &'世界 高さ場の読み口, 候補の選別: 静的世界の候補の選別<'世界>) -> Self {
        Self {
            高さ場の読み口, 候補の選別
        }
    }

    pub(super) fn 高さ場の読み口(&self) -> &'世界 高さ場の読み口 {
        self.高さ場の読み口
    }

    pub(super) fn 候補の選別(&self) -> &静的世界の候補の選別<'世界> {
        &self.候補の選別
    }
}
