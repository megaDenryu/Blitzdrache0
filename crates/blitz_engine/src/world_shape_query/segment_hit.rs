//! 線分が最初に当たる世界の形。地形に当たる枝と建物に当たる枝を分けるのは、当たった相手の種別によって
//! 答えが持てる事実が違うためである。
//!
//! 地形の当たりは升目の地表の面(高さ・法線・接線・どの升目のどちらの三角形か)を持つ。建物の当たりは
//! 衝突対象の安定識別子と子形状識別子と直方体のどの特徴かを持つ。1つの型へ潰すと、どちらの枝にも意味のない
//! 値なしの欄が並ぶ。

use crate::height_field::線分と地表の当たり;

use super::building_hit::線分と建物の当たり;

/// 線分が最初に当たる世界の形。何にも当たらない枝と、地形に当たる枝と、建物に当たる枝の3つである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 線分が最初に当たる世界の形<'形状> {
    /// 終点まで地形にも建物にも当たらなかった。
    何にも当たらない,
    /// 地形の地表に最初に当たった。
    地形に当たる(線分と地表の当たり),
    /// 建物の子形状に最初に当たった。
    建物に当たる(線分と建物の当たり<'形状>),
}
