//! 地形の答えと建物の答えを1つの答えへ畳む決まり。線分の問い合わせと掃引の問い合わせが共有する。
//!
//! 完全性は、どちらか一方でも「評価できない領域を含む」なら合成もそうなる。範囲の一部が分からないまま
//! 「対象範囲を完全に評価できた」と答えると、呼び出し側が「この範囲に当たりは無い」と読んでしまう。
//!
//! 時刻が並んだときは地形を残す。地形を先に評価する順が固定であり、同じ入力から同じ答えが出るためである。
//! どちらを残しても、その時刻に2つの形が同時に触れているという事実は変わらない。

use crate::world_query::問い合わせ完全性;

pub(super) enum 地形と建物のどちらが先か {
    どちらも当たらない,
    地形が先,
    建物が先,
}

impl 地形と建物のどちらが先か {
    // 先に当たると決めたほうの時刻。どちらにも当たらないなら値なしである。切り詰める先を決めるのに使う。
    pub(super) fn 選んだ側の時刻を求める(&self, 地形の時刻: Option<f64>, 建物の時刻: Option<f64>) -> Option<f64> {
        match self {
            Self::どちらも当たらない => None,
            Self::地形が先 => 地形の時刻,
            Self::建物が先 => 建物の時刻,
        }
    }

    // 2つの時刻から先に当たるほうを決める。値なしはその相手に当たらなかったことを表す。
    pub(super) fn 二つの時刻から決める(地形の時刻: Option<f64>, 建物の時刻: Option<f64>) -> Self {
        match (地形の時刻, 建物の時刻) {
            (None, None) => Self::どちらも当たらない,
            (Some(_), None) => Self::地形が先,
            (None, Some(_)) => Self::建物が先,
            (Some(地形), Some(建物)) => {
                if 建物 < 地形 {
                    Self::建物が先
                } else {
                    Self::地形が先
                }
            }
        }
    }
}

pub(super) fn 二つの完全性を畳む(一方: 問い合わせ完全性, 他方: 問い合わせ完全性) -> 問い合わせ完全性 {
    match (一方, 他方) {
        (問い合わせ完全性::対象範囲を完全に評価できた, 問い合わせ完全性::対象範囲を完全に評価できた) => {
            問い合わせ完全性::対象範囲を完全に評価できた
        }
        _ => 問い合わせ完全性::評価できない領域を含む,
    }
}
