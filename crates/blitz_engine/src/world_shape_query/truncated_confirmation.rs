//! 見つけた当たりを確定として返せるかを、当たりの時刻までへ切り詰めた覆いで確かめ直す工程。受け取るのは
//! 問い合わせの入力と、合成した完全性と地形の完全性と当たりの時刻から決めた判断、返すのは答えに載せる完全性である。
//!
//! これが要るのは、建物の側の完全性が覆い全体の集計であり、読み込まれていないチャンクが当たりより手前に在るのか
//! 奥に在るのかを持たないためである。読込済みの箱に始めから重なっている入力でも、掃引の覆いが後方の未読込チャンクへ
//! 届くだけで確定した接触が捨てられていた。当たりより手前へ切り詰めた覆いが完全なら、その当たりより早い当たりは
//! 在りえないため、答えは確定する。
//!
//! 地形の側を切り詰めて問い直さないのは、高さ場の走査が線分に沿った順であり、打ち切りが当たらなかった側にしか
//! 現れないためである。地形が当たりを返したならその手前は評価し終えている。地形が打ち切りで返したときは、止まった
//! 場所が当たりより手前か奥かを答えとして持たないため、従来どおり当たりを捨てる。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断8: 問い合わせの値と完全性を別軸にする」

use blitz_math::{メートル, ワールド, 変位, 大域ワールド位置};

use crate::world_query::問い合わせ完全性;

use super::error::世界の形への問い合わせエラー;
use super::query::世界の形への問い合わせ;

#[derive(Clone, Copy)]
pub(super) enum 切り詰めて問い直す必要があるか {
    問い直さずに決まった完全性(問い合わせ完全性),
    切り詰めて問い直す { 当たりの時刻: f64 },
}

impl 切り詰めて問い直す必要があるか {
    // 合成した完全性が既に完全なら問い直す必要は無い。落ちているときは、地形の側が完全でありかつ当たりが在る場合に
    // 限って、建物の側を当たりの時刻までへ切り詰めて問い直す余地がある。
    pub(super) fn 完全性と当たりの時刻から決める(
        合成した完全性: 問い合わせ完全性,
        地形の完全性: 問い合わせ完全性,
        当たりの時刻: Option<f64>,
    ) -> Self {
        if 合成した完全性 == 問い合わせ完全性::対象範囲を完全に評価できた {
            return Self::問い直さずに決まった完全性(問い合わせ完全性::対象範囲を完全に評価できた);
        }
        match (地形の完全性, 当たりの時刻) {
            (問い合わせ完全性::対象範囲を完全に評価できた, Some(当たりの時刻)) => {
                Self::切り詰めて問い直す { 当たりの時刻 }
            }
            _ => Self::問い直さずに決まった完全性(問い合わせ完全性::評価できない領域を含む),
        }
    }
}

impl<'世界> 世界の形への問い合わせ<'世界> {
    pub(super) fn 線分の当たりを切り詰めて確かめた完全性を求める(
        &self,
        始点: 大域ワールド位置,
        終点: 大域ワールド位置,
        判断: 切り詰めて問い直す必要があるか,
    ) -> Result<問い合わせ完全性, 世界の形への問い合わせエラー> {
        match 判断 {
            切り詰めて問い直す必要があるか::問い直さずに決まった完全性(完全性) => Ok(完全性),
            切り詰めて問い直す必要があるか::切り詰めて問い直す { 当たりの時刻 } => Ok(self
                .候補の選別()
                .線分を当たりの時刻まで切り詰めた覆いの完全性を求める(始点, 終点, 当たりの時刻)?),
        }
    }

    pub(super) fn 掃引の接触を切り詰めて確かめた完全性を求める(
        &self,
        軸の始点: 大域ワールド位置,
        軸の終点: 大域ワールド位置,
        半径: メートル,
        掃引の変位: 変位<ワールド>,
        判断: 切り詰めて問い直す必要があるか,
    ) -> Result<問い合わせ完全性, 世界の形への問い合わせエラー> {
        match 判断 {
            切り詰めて問い直す必要があるか::問い直さずに決まった完全性(完全性) => Ok(完全性),
            切り詰めて問い直す必要があるか::切り詰めて問い直す { 当たりの時刻 } => Ok(self
                .候補の選別()
                .掃引を接触の割合まで切り詰めた覆いの完全性を求める(軸の始点, 軸の終点, 半径, 掃引の変位, 当たりの時刻)?),
        }
    }
}
