//! 掃引したカプセルが建物の子形状に最初に触れた点を、世界の語彙で表した値。
//!
//! 持つのは幾何学的な事実と所在だけである。地形の接触と同じく、接する平面の情報は持たない。
//! 辺と頂点に触れたときはその点で接する平面が定まらないためである。

use blitz_collision::height_field::掃引で動けた割合;
use blitz_collision::oriented_box::直方体で当たった特徴;
use blitz_math::{ワールド, 大域ワールド位置, 方向};

use super::building_place::建物の子形状の所在;

/// 掃引したカプセルが建物の子形状へ触れた1つの事実。動けた割合・接触の大域位置・接触の単位法線・所在・触れた特徴を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct カプセルと建物の接触<'形状> {
    動けた割合: 掃引で動けた割合,
    接触の大域位置: 大域ワールド位置,
    接触の単位法線: 方向<ワールド>,
    所在: 建物の子形状の所在<'形状>,
    触れた特徴: 直方体で当たった特徴,
}

impl<'形状> カプセルと建物の接触<'形状> {
    pub(super) fn 生成する(
        動けた割合: 掃引で動けた割合,
        接触の大域位置: 大域ワールド位置,
        接触の単位法線: 方向<ワールド>,
        所在: 建物の子形状の所在<'形状>,
        触れた特徴: 直方体で当たった特徴,
    ) -> Self {
        Self {
            動けた割合,
            接触の大域位置,
            接触の単位法線,
            所在,
            触れた特徴,
        }
    }

    /// 掃引の変位のうち、建物に触れるまでに動けた分の割合。動く前から触れていた場合は0である。
    pub fn 動けた割合(&self) -> 掃引で動けた割合 {
        self.動けた割合
    }

    /// 接触の点の大域ワールド位置。
    pub fn 接触の大域位置(&self) -> 大域ワールド位置 {
        self.接触の大域位置
    }

    /// 接触位置からカプセルの軸へ向かう単位方向。
    pub fn 接触の単位法線(&self) -> 方向<ワールド> {
        self.接触の単位法線
    }

    /// 触れた子形状がどのチャンクのどの衝突対象のどれか。
    pub fn 所在(&self) -> 建物の子形状の所在<'形状> {
        self.所在
    }

    /// 子形状の直方体の面・辺・頂点のどれに触れたか。
    pub fn 触れた特徴(&self) -> 直方体で当たった特徴 {
        self.触れた特徴
    }
}
