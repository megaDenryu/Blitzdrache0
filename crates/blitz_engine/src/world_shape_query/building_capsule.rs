//! 候補に挙がった子形状を1件ずつ辿り、掃引したカプセルが最初に触れる建物を求める工程。受け取るのは軸の両端と
//! 半径と掃引の変位と候補の一覧、返すのは最も早い接触である。
//!
//! 候補の順は選別が固定している。動けた割合が並んだときは先に挙がった候補を残すため、答えは入力だけで決まる。

use blitz_collision::oriented_box::{カプセルが直方体に最初に触れる点, 直方体のカプセルの掃引の問い合わせ};
use blitz_collision::shape::形を掃引するカプセル;
use blitz_math::{メートル, ワールド, 変位, 大域ワールド位置};

use super::building_contact::カプセルと建物の接触;
use super::building_place::建物の子形状の所在;
use super::error::世界の形への問い合わせエラー;
use super::local_frame::{
    世界の変位を局所座標の変位へ写す, 大域位置をチャンクの局所座標へ写す, 局所座標の位置を大域へ写す, 局所座標の方向を世界へ写す,
};
use super::query::世界の形への問い合わせ;
use crate::static_shape::index::静的な子形状の候補;

impl<'世界> 世界の形への問い合わせ<'世界> {
    pub(super) fn 候補の中でカプセルが最初に触れる建物を求める(
        &self,
        軸の始点: 大域ワールド位置,
        軸の終点: 大域ワールド位置,
        半径: メートル,
        掃引の変位: 変位<ワールド>,
        候補一覧: &[静的な子形状の候補<'世界>],
    ) -> Result<Option<カプセルと建物の接触<'世界>>, 世界の形への問い合わせエラー> {
        let mut 最も早い接触: Option<カプセルと建物の接触<'世界>> = None;
        for 候補 in 候補一覧 {
            let Some(接触) = self.子形状1件への掃引の接触を求める(軸の始点, 軸の終点, 半径, 掃引の変位, 候補)?
            else {
                continue;
            };
            if 最も早い接触.is_none_or(|これまで| 接触.動けた割合() < これまで.動けた割合()) {
                最も早い接触 = Some(接触);
            }
        }
        Ok(最も早い接触)
    }

    // 候補1件の直方体への詳細判定。カプセルをその候補のチャンクの局所座標へ写してから解き、答えを世界の語彙へ戻す。
    fn 子形状1件への掃引の接触を求める(
        &self,
        軸の始点: 大域ワールド位置,
        軸の終点: 大域ワールド位置,
        半径: メートル,
        掃引の変位: 変位<ワールド>,
        候補: &静的な子形状の候補<'世界>,
    ) -> Result<Option<カプセルと建物の接触<'世界>>, 世界の形への問い合わせエラー> {
        let 大域原点 = 候補.チャンクの大域原点();
        let カプセル = 形を掃引するカプセル::生成する(
            大域位置をチャンクの局所座標へ写す(軸の始点, 大域原点)?,
            大域位置をチャンクの局所座標へ写す(軸の終点, 大域原点)?,
            f64::from(半径.値()),
            世界の変位を局所座標の変位へ写す(掃引の変位)?,
        )?;
        let 問い合わせ = 直方体のカプセルの掃引の問い合わせ::直方体から生成する(&候補.直方体());
        match 問い合わせ.カプセルが直方体に最初に触れる点を求める(&カプセル)? {
            カプセルが直方体に最初に触れる点::直方体に触れない => Ok(None),
            カプセルが直方体に最初に触れる点::直方体に触れる(接触) => Ok(Some(カプセルと建物の接触::生成する(
                接触.動けた割合(),
                局所座標の位置を大域へ写す(接触.接触位置(), 大域原点),
                局所座標の方向を世界へ写す(接触.接触の単位法線())?,
                建物の子形状の所在::生成する(候補.チャンク座標(), 候補.衝突対象の安定識別子(), 候補.子形状識別子()),
                接触.触れた特徴(),
            ))),
        }
    }
}
