//! 線分が建物の子形状に最初に当たった点を、世界の語彙で表した値。
//!
//! 持つのは幾何学的な事実と所在だけである。壁か床か、そこで止まるか登れるかという意味付けは持たない。
//! 交差位置を大域ワールドの位置で返すのは、呼び出し側がチャンクの区画を知らずに答えを使えるようにするためである。

use blitz_collision::height_field::線分の媒介変数;
use blitz_collision::oriented_box::直方体で当たった特徴;
use blitz_math::{ワールド, 大域ワールド位置, 方向};

use super::building_place::建物の子形状の所在;

/// 線分が建物の子形状に最初に当たった1つの事実。交差時刻・交差の大域位置・接触面の単位法線・所在・当たった特徴を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 線分と建物の当たり<'形状> {
    交差時刻: 線分の媒介変数,
    交差の大域位置: 大域ワールド位置,
    接触面の単位法線: 方向<ワールド>,
    所在: 建物の子形状の所在<'形状>,
    当たった特徴: 直方体で当たった特徴,
}

impl<'形状> 線分と建物の当たり<'形状> {
    pub(super) fn 生成する(
        交差時刻: 線分の媒介変数,
        交差の大域位置: 大域ワールド位置,
        接触面の単位法線: 方向<ワールド>,
        所在: 建物の子形状の所在<'形状>,
        当たった特徴: 直方体で当たった特徴,
    ) -> Self {
        Self {
            交差時刻,
            交差の大域位置,
            接触面の単位法線,
            所在,
            当たった特徴,
        }
    }

    /// 線分の始点を0、終点を1として測った、最初に建物へ達した時刻。始点が既に子形状の中にある線分では0になる。
    pub fn 交差時刻(&self) -> 線分の媒介変数 {
        self.交差時刻
    }

    /// 交差の点の大域ワールド位置。
    pub fn 交差の大域位置(&self) -> 大域ワールド位置 {
        self.交差の大域位置
    }

    /// 当たった特徴の外側を向く単位方向。
    pub fn 接触面の単位法線(&self) -> 方向<ワールド> {
        self.接触面の単位法線
    }

    /// 当たった子形状がどのチャンクのどの衝突対象のどれか。
    pub fn 所在(&self) -> 建物の子形状の所在<'形状> {
        self.所在
    }

    /// 子形状の直方体の面・辺・頂点のどれに当たったか。
    pub fn 当たった特徴(&self) -> 直方体で当たった特徴 {
        self.当たった特徴
    }
}
