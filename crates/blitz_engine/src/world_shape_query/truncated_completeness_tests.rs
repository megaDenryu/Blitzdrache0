//! 覆いの完全性が落ちた問い合わせを、当たりまで切り詰めた覆いで確かめ直すことの反証。
//!
//! 読込済みのチャンクは建物を置いた1件だけであるため、覆いが東へ64メートルを越えると隣のチャンクが未読込として
//! 数えられ、覆い全体の完全性が落ちる。地形は持たない世界を使い、地形の側の完全性を常に完全に保つ。
//!
//! 見るのは3つである。当たりより後ろだけが未読込の掃引が確定した接触を返すこと、当たりのところで既に未読込へ
//! かかる掃引が従来どおり捨てられること、線分でも同じ切り詰めが働くことである。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 変位, 方向};

use crate::static_shape::index::静的な子形状の候補;
use crate::world_query::問い合わせ完全性;

use super::capsule_hit::掃引したカプセルが最初に触れる世界の形;
use super::segment_hit::線分が最初に当たる世界の形;
use super::world_query_fixture::{問い合わせを組む, 地形を持たない読み口, 大域位置, 箱を1つ置いた保管};

// 東へ100メートル進む掃引。覆いの東の端がチャンクの一辺64メートルを越えるため、隣の未読込チャンクが覆いに入る。
fn 東へ百メートルの掃引() -> 変位<ワールド> {
    変位::方向へ進む(方向::<ワールド>::生成する(1.0, 0.0, 0.0).unwrap(), メートル::生成する(100.0))
}

#[test]
fn 接触より後ろだけが未読込の掃引は確定した接触を返す() {
    let 読み口 = 地形を持たない読み口();
    let 保管 = 箱を1つ置いた保管([11.0, 4.5, 45.0], [0.5, 0.25, 0.5]);
    let 問い合わせ = 問い合わせを組む(&読み口, &保管);
    let mut 受け皿: Vec<静的な子形状の候補<'_>> = Vec::new();
    let 答え = 問い合わせ
        .掃引したカプセルが最初に触れる世界の形を求める(
            大域位置(9.0, 4.5, -19.0),
            大域位置(9.0, 5.5, -19.0),
            メートル::生成する(0.5),
            東へ百メートルの掃引(),
            &mut 受け皿,
        )
        .unwrap();
    assert_eq!(答え.完全性(), 問い合わせ完全性::対象範囲を完全に評価できた);
    let 掃引したカプセルが最初に触れる世界の形::建物に触れる(接触) = *答え.値() else {
        panic!("東へ1メートル先の箱の西の面に触れなかった");
    };
    assert!((接触.動けた割合().値() - 0.01).abs() <= 1.0e-9, "動けた割合{}", 接触.動けた割合().値());
}

#[test]
fn 接触のところで既に未読込へかかる掃引は接触を捨てる() {
    let 読み口 = 地形を持たない読み口();
    let 保管 = 箱を1つ置いた保管([63.5, 4.5, 45.0], [0.5, 0.25, 0.5]);
    let 問い合わせ = 問い合わせを組む(&読み口, &保管);
    let mut 受け皿: Vec<静的な子形状の候補<'_>> = Vec::new();
    let 答え = 問い合わせ
        .掃引したカプセルが最初に触れる世界の形を求める(
            大域位置(63.8, 5.0, -19.0),
            大域位置(63.8, 6.0, -19.0),
            メートル::生成する(0.5),
            東へ百メートルの掃引(),
            &mut 受け皿,
        )
        .unwrap();
    assert_eq!(答え.完全性(), 問い合わせ完全性::評価できない領域を含む);
    assert_eq!(*答え.値(), 掃引したカプセルが最初に触れる世界の形::何にも触れない);
}

#[test]
fn 当たりより後ろだけが未読込の線分は確定した当たりを返す() {
    let 読み口 = 地形を持たない読み口();
    let 保管 = 箱を1つ置いた保管([11.0, 4.5, 45.0], [0.5, 0.25, 0.5]);
    let 問い合わせ = 問い合わせを組む(&読み口, &保管);
    let mut 受け皿: Vec<静的な子形状の候補<'_>> = Vec::new();
    let 答え = 問い合わせ
        .線分が最初に当たる世界の形を求める(大域位置(11.0, 5.5, -19.0), 大域位置(75.0, -250.5, -19.0), &mut 受け皿)
        .unwrap();
    assert_eq!(答え.完全性(), 問い合わせ完全性::対象範囲を完全に評価できた);
    let 線分が最初に当たる世界の形::建物に当たる(当たり) = *答え.値() else {
        panic!("箱の天面に当たらなかった");
    };
    assert_eq!(当たり.交差時刻().値(), 0.75 / 256.0);
    assert_eq!(当たり.交差の大域位置(), 大域位置(11.1875, 4.75, -19.0));
}
