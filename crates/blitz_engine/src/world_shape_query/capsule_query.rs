//! 掃引したカプセルが地形と建物のどちらに先に触れるかを答える入口。受け取るのは軸の両端と半径と掃引の変位と
//! 候補の受け皿、返すのは最初に触れる世界の形と、そのどちらの側も含めた完全性である。
//!
//! 畳み方は線分の入口と同じである。地形を先に評価し、次に建物の候補を選別して1件ずつ詳細判定にかける。
//! どちらか一方でも「評価できない領域を含む」なら、見つけた接触を捨てて「何にも触れない」の側で答える。

use blitz_math::{メートル, ワールド, 変位, 大域ワールド位置};

use crate::height_field::{
    掃引したカプセルが最初に触れる地表, 掃引したカプセルが最初に触れる地表の問い合わせ結果
};
use crate::static_shape::index::静的な子形状の候補;
use crate::world_query::{世界問い合わせ結果, 問い合わせ完全性};

use super::capsule_hit::掃引したカプセルが最初に触れる世界の形;
use super::composition::{二つの完全性を畳む, 地形と建物のどちらが先か};
use super::error::世界の形への問い合わせエラー;
use super::query::世界の形への問い合わせ;

impl<'世界> 世界の形への問い合わせ<'世界> {
    /// 軸の両端と半径で決まるカプセルを掃引の変位だけ動かしたとき、地形と建物のどちらに最初に触れるかを求める。
    pub fn 掃引したカプセルが最初に触れる世界の形を求める(
        &self,
        軸の始点: 大域ワールド位置,
        軸の終点: 大域ワールド位置,
        半径: メートル,
        掃引の変位: 変位<ワールド>,
        受け皿: &mut Vec<静的な子形状の候補<'世界>>,
    ) -> Result<世界問い合わせ結果<掃引したカプセルが最初に触れる世界の形<'世界>>, 世界の形への問い合わせエラー> {
        let 地形 = self.掃引したカプセルが最初に触れる地形を求める(軸の始点, 軸の終点, 半径, 掃引の変位)?;
        let 建物の完全性 =
            self.候補の選別()
                .掃引したカプセルに触れうる子形状の候補を集める(軸の始点, 軸の終点, 半径, 掃引の変位, 受け皿)?;
        let 建物 = self.候補の中でカプセルが最初に触れる建物を求める(軸の始点, 軸の終点, 半径, 掃引の変位, 受け皿)?;
        let 完全性 = 二つの完全性を畳む(地形.完全性(), 建物の完全性);
        if 完全性 == 問い合わせ完全性::評価できない領域を含む {
            return Ok(世界問い合わせ結果::生成する(
                掃引したカプセルが最初に触れる世界の形::何にも触れない,
                完全性,
            ));
        }
        let 先 = 地形と建物のどちらが先か::二つの時刻から決める(
            地形.値().map(|接触| 接触.動けた割合().値()),
            建物.map(|接触| 接触.動けた割合().値()),
        );
        Ok(世界問い合わせ結果::生成する(
            先に触れる形を選ぶ(先, *地形.値(), 建物),
            完全性,
        ))
    }

    // 地形の側の答え。高さ場を持たない世界は「地形に触れない」を確定した答えとして返す。
    fn 掃引したカプセルが最初に触れる地形を求める(
        &self,
        軸の始点: 大域ワールド位置,
        軸の終点: 大域ワールド位置,
        半径: メートル,
        掃引の変位: 変位<ワールド>,
    ) -> Result<世界問い合わせ結果<Option<crate::height_field::カプセルと地表の接触>>, 世界の形への問い合わせエラー> {
        let 答え = self
            .高さ場の読み口()
            .掃引したカプセルが最初に触れる地表を求める(軸の始点, 軸の終点, 半径, 掃引の変位);
        match 答え {
            掃引したカプセルが最初に触れる地表の問い合わせ結果::高さ場を持たない世界 => Ok(
                世界問い合わせ結果::生成する(None, 問い合わせ完全性::対象範囲を完全に評価できた),
            ),
            掃引したカプセルが最初に触れる地表の問い合わせ結果::カプセルの掃引を評価できない(誤り) => {
                Err(誤り.into())
            }
            掃引したカプセルが最初に触れる地表の問い合わせ結果::カプセルの掃引を評価した結果(答え) => {
                let 接触 = match 答え.値() {
                    掃引したカプセルが最初に触れる地表::地表に触れない => None,
                    掃引したカプセルが最初に触れる地表::地表に触れる(接触) => Some(*接触),
                };
                Ok(世界問い合わせ結果::生成する(接触, 答え.完全性()))
            }
        }
    }
}

// 先に触れる側の答えを枝へ写す。どちらが先かの判定は`composition.rs`が済ませている。
fn 先に触れる形を選ぶ<'世界>(
    先: 地形と建物のどちらが先か,
    地形: Option<crate::height_field::カプセルと地表の接触>,
    建物: Option<super::building_contact::カプセルと建物の接触<'世界>>,
) -> 掃引したカプセルが最初に触れる世界の形<'世界> {
    match (先, 地形, 建物) {
        (地形と建物のどちらが先か::地形が先, Some(接触), _) => {
            掃引したカプセルが最初に触れる世界の形::地形に触れる(接触)
        }
        (地形と建物のどちらが先か::建物が先, _, Some(接触)) => {
            掃引したカプセルが最初に触れる世界の形::建物に触れる(接触)
        }
        _ => 掃引したカプセルが最初に触れる世界の形::何にも触れない,
    }
}
