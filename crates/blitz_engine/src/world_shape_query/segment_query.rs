//! 線分が地形と建物のどちらに先に当たるかを答える入口。受け取るのは線分の両端と候補の受け皿、返すのは
//! 最初に当たる世界の形と、そのどちらの側も含めた完全性である。
//!
//! 地形を先に評価し、次に建物の候補を選別して1件ずつ詳細判定にかける。地形の答えと建物の答えを畳む決まりは
//! `composition.rs`が持つ。どちらか一方でも「評価できない領域を含む」なら、見つけた当たりを捨てて
//! 「何にも当たらない」の側で答える。打ち切りより手前に別の当たりがありうるからである。

use blitz_math::大域ワールド位置;

use crate::height_field::{線分が最初に当たる地表, 線分が最初に当たる地表の問い合わせ結果};
use crate::static_shape::index::静的な子形状の候補;
use crate::world_query::{世界問い合わせ結果, 問い合わせ完全性};

use super::composition::{二つの完全性を畳む, 地形と建物のどちらが先か};
use super::error::世界の形への問い合わせエラー;
use super::query::世界の形への問い合わせ;
use super::segment_hit::線分が最初に当たる世界の形;

impl<'世界> 世界の形への問い合わせ<'世界> {
    /// 始点から終点へ引いた線分が、地形と建物のどちらに最初に当たるかを求める。受け皿は候補の選別が入口で空にする。
    pub fn 線分が最初に当たる世界の形を求める(
        &self,
        始点: 大域ワールド位置,
        終点: 大域ワールド位置,
        受け皿: &mut Vec<静的な子形状の候補<'世界>>,
    ) -> Result<世界問い合わせ結果<線分が最初に当たる世界の形<'世界>>, 世界の形への問い合わせエラー> {
        let 地形 = self.線分が最初に当たる地形を求める(始点, 終点)?;
        let 建物の完全性 = self.候補の選別().線分に触れうる子形状の候補を集める(始点, 終点, 受け皿)?;
        let 建物 = self.候補の中で線分が最初に当たる建物を求める(始点, 終点, 受け皿)?;
        let 完全性 = 二つの完全性を畳む(地形.完全性(), 建物の完全性);
        if 完全性 == 問い合わせ完全性::評価できない領域を含む {
            return Ok(世界問い合わせ結果::生成する(
                線分が最初に当たる世界の形::何にも当たらない,
                完全性,
            ));
        }
        let 先 = 地形と建物のどちらが先か::二つの時刻から決める(
            地形.値().map(|当たり| 当たり.交差時刻().値()),
            建物.map(|当たり| 当たり.交差時刻().値()),
        );
        Ok(世界問い合わせ結果::生成する(
            先に当たる形を選ぶ(先, *地形.値(), 建物),
            完全性,
        ))
    }

    // 地形の側の答え。高さ場を持たない世界は「地形に当たらない」を確定した答えとして返す。地形が1つも
    // 無い世界では、地形に当たらないことが調べるまでもなく決まっているためである。
    fn 線分が最初に当たる地形を求める(
        &self,
        始点: 大域ワールド位置,
        終点: 大域ワールド位置,
    ) -> Result<世界問い合わせ結果<Option<crate::height_field::線分と地表の当たり>>, 世界の形への問い合わせエラー> {
        match self.高さ場の読み口().線分が最初に当たる地表を求める(始点, 終点) {
            線分が最初に当たる地表の問い合わせ結果::高さ場を持たない世界 => Ok(
                世界問い合わせ結果::生成する(None, 問い合わせ完全性::対象範囲を完全に評価できた),
            ),
            線分が最初に当たる地表の問い合わせ結果::線分を評価できない(誤り) => Err(誤り.into()),
            線分が最初に当たる地表の問い合わせ結果::線分を評価した結果(答え) => {
                let 当たり = match 答え.値() {
                    線分が最初に当たる地表::地表に当たらない => None,
                    線分が最初に当たる地表::地表に当たる(当たり) => Some(*当たり),
                };
                Ok(世界問い合わせ結果::生成する(当たり, 答え.完全性()))
            }
        }
    }
}

// 先に当たる側の答えを枝へ写す。どちらが先かの判定は`composition.rs`が済ませている。
fn 先に当たる形を選ぶ<'世界>(
    先: 地形と建物のどちらが先か,
    地形: Option<crate::height_field::線分と地表の当たり>,
    建物: Option<super::building_hit::線分と建物の当たり<'世界>>,
) -> 線分が最初に当たる世界の形<'世界> {
    match (先, 地形, 建物) {
        (地形と建物のどちらが先か::地形が先, Some(当たり), _) => {
            線分が最初に当たる世界の形::地形に当たる(当たり)
        }
        (地形と建物のどちらが先か::建物が先, _, Some(当たり)) => {
            線分が最初に当たる世界の形::建物に当たる(当たり)
        }
        _ => 線分が最初に当たる世界の形::何にも当たらない,
    }
}
