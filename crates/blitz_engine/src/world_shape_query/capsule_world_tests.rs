//! 掃引したカプセルが地形と建物のどちらに先に触れるかの反証と、同じ問い合わせを2度評価した答えのビット一致。
//!
//! 期待値は手で解く。半径0.5メートルのカプセルの下端が高さ6.75メートルから真下へ4メートル動くとき、
//! 天面が高さ4.75メートルの箱へ触れるのは下端が5.25メートルまで下りた時点である。1.5メートル降りたところで
//! あるから、動けた割合は0.375になる。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 変位, 方向};

use crate::static_shape::index::静的な子形状の候補;
use crate::world_query::問い合わせ完全性;

use super::capsule_hit::掃引したカプセルが最初に触れる世界の形;
use super::segment_hit::線分が最初に当たる世界の形;
use super::world_query_fixture::{問い合わせを組む, 地形を持つ読み口, 大域位置, 箱を1つ置いた保管};

#[test]
fn 掃引したカプセルは地形より手前の建物の天面に触れる() {
    let 読み口 = 地形を持つ読み口();
    let 保管 = 箱を1つ置いた保管([11.0, 4.5, 45.0], [0.5, 0.25, 0.5]);
    let 問い合わせ = 問い合わせを組む(&読み口, &保管);
    let mut 受け皿: Vec<静的な子形状の候補<'_>> = Vec::new();
    let 下向き = 変位::方向へ進む(方向::<ワールド>::生成する(0.0, -1.0, 0.0).unwrap(), メートル::生成する(4.0));
    let 答え = 問い合わせ
        .掃引したカプセルが最初に触れる世界の形を求める(
            大域位置(11.0, 6.75, -19.0),
            大域位置(11.0, 8.75, -19.0),
            メートル::生成する(0.5),
            下向き,
            &mut 受け皿,
        )
        .unwrap();
    assert_eq!(答え.完全性(), 問い合わせ完全性::対象範囲を完全に評価できた);
    let 掃引したカプセルが最初に触れる世界の形::建物に触れる(接触) = *答え.値() else {
        panic!("建物に触れなかった");
    };
    assert_eq!(接触.動けた割合().値(), 0.375);
    assert_eq!(接触.接触の大域位置(), 大域位置(11.0, 4.75, -19.0));
    assert_eq!(接触.接触の単位法線(), 方向::<ワールド>::生成する(0.0, 1.0, 0.0).unwrap());
    assert_eq!(接触.所在().衝突対象の安定識別子().綴り(), "試験の建物");
}

#[test]
fn 同じ問い合わせを二度評価しても答えのビット列が一致する() {
    let 読み口 = 地形を持つ読み口();
    let 保管 = 箱を1つ置いた保管([11.0, 4.5, 45.0], [0.5, 0.25, 0.5]);
    let 問い合わせ = 問い合わせを組む(&読み口, &保管);
    let mut 受け皿: Vec<静的な子形状の候補<'_>> = Vec::new();
    let 一度目 = 問い合わせ
        .線分が最初に当たる世界の形を求める(大域位置(11.0, 5.5, -19.0), 大域位置(11.0, 1.5, -19.0), &mut 受け皿)
        .unwrap();
    let 二度目 = 問い合わせ
        .線分が最初に当たる世界の形を求める(大域位置(11.0, 5.5, -19.0), 大域位置(11.0, 1.5, -19.0), &mut 受け皿)
        .unwrap();
    let (線分が最初に当たる世界の形::建物に当たる(一), 線分が最初に当たる世界の形::建物に当たる(二)) = (*一度目.値(), *二度目.値())
    else {
        panic!("2回とも建物に当たるはずである");
    };
    assert_eq!(一.交差時刻().値().to_bits(), 二.交差時刻().値().to_bits());
    assert_eq!(一.交差の大域位置(), 二.交差の大域位置());
    assert_eq!(一.当たった特徴(), 二.当たった特徴());
}
