//! 建物の子形状の所在: 当たった相手がどのチャンクのどの衝突対象のどの子形状かを指す3つ組である。
//!
//! 幾何の値(位置・法線・時刻)と別の型にするのは、所在が世界の台帳の話であって形の幾何ではないためである。
//! 線分の当たりとカプセルの接触が同じ所在を持つため、2つの答えの型がこれを共有する。
//!
//! 綴りを参照で持つのは、綴りが可変長の文字列であり、答え1件ごとに確保を起こさないためである。参照の寿命は
//! 形状の保管の寿命であり、そのチャンクが解除されるまで生きる。
//! 参照: `_doc/設計/世界の形と衝突基盤.md`「判断9: 複合形状は子形状を束ねて1つの衝突対象にする」

use crate::static_shape::{子形状識別子, 衝突対象の安定識別子};
use crate::チャンク座標;

/// 当たった建物の子形状を指す所在。チャンク座標・親の衝突対象の安定識別子・子形状識別子の3つで決まる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 建物の子形状の所在<'形状> {
    チャンク座標: チャンク座標,
    衝突対象の安定識別子: &'形状 衝突対象の安定識別子,
    子形状識別子: 子形状識別子,
}

impl<'形状> 建物の子形状の所在<'形状> {
    pub(super) fn 生成する(
        チャンク座標: チャンク座標, 衝突対象の安定識別子: &'形状 衝突対象の安定識別子, 子形状識別子: 子形状識別子
    ) -> Self {
        Self {
            チャンク座標,
            衝突対象の安定識別子,
            子形状識別子,
        }
    }

    /// 当たった子形状が属するチャンクの座標。
    pub fn チャンク座標(&self) -> チャンク座標 {
        self.チャンク座標
    }

    /// 当たった子形状が属する衝突対象を、そのチャンクの中で指す綴り。
    pub fn 衝突対象の安定識別子(&self) -> &'形状 衝突対象の安定識別子 {
        self.衝突対象の安定識別子
    }

    /// 当たった子形状を、その衝突対象の中で指す番号。
    pub fn 子形状識別子(&self) -> 子形状識別子 {
        self.子形状識別子
    }
}
