//! 候補に挙がった子形状を1件ずつ辿り、線分が最初に当たる建物を求める工程。受け取るのは線分の両端と候補の一覧、
//! 返すのは最も早い当たりである。
//!
//! 候補の順は選別が固定している(チャンク座標の昇順・衝突対象を焼いた順・子形状を据えた順)。時刻が並んだときは
//! 先に挙がった候補を残すため、答えは入力だけで決まる。
//!
//! 候補ごとに直方体を倍精度で読み直すのは、候補が問い合わせのたびに変わるためである。形1つにつき1回の
//! 読み直しであり、その費用は候補の件数に比例する。

use blitz_collision::oriented_box::{直方体の線分の問い合わせ, 線分が直方体に最初に当たる点};
use blitz_collision::shape::形を貫く線分;
use blitz_math::大域ワールド位置;

use super::building_hit::線分と建物の当たり;
use super::building_place::建物の子形状の所在;
use super::error::世界の形への問い合わせエラー;
use super::local_frame::{
    大域位置をチャンクの局所座標へ写す, 局所座標の位置を大域へ写す, 局所座標の方向を世界へ写す
};
use super::query::世界の形への問い合わせ;
use crate::static_shape::index::静的な子形状の候補;

impl<'世界> 世界の形への問い合わせ<'世界> {
    pub(super) fn 候補の中で線分が最初に当たる建物を求める(
        &self,
        始点: 大域ワールド位置,
        終点: 大域ワールド位置,
        候補一覧: &[静的な子形状の候補<'世界>],
    ) -> Result<Option<線分と建物の当たり<'世界>>, 世界の形への問い合わせエラー> {
        let mut 最も早い当たり: Option<線分と建物の当たり<'世界>> = None;
        for 候補 in 候補一覧 {
            let Some(当たり) = self.子形状1件への線分の当たりを求める(始点, 終点, 候補)? else {
                continue;
            };
            if 最も早い当たり.is_none_or(|これまで| 当たり.交差時刻() < これまで.交差時刻()) {
                最も早い当たり = Some(当たり);
            }
        }
        Ok(最も早い当たり)
    }

    // 候補1件の直方体への詳細判定。線分をその候補のチャンクの局所座標へ写してから解き、答えを世界の語彙へ戻す。
    fn 子形状1件への線分の当たりを求める(
        &self,
        始点: 大域ワールド位置,
        終点: 大域ワールド位置,
        候補: &静的な子形状の候補<'世界>,
    ) -> Result<Option<線分と建物の当たり<'世界>>, 世界の形への問い合わせエラー> {
        let 大域原点 = 候補.チャンクの大域原点();
        let 線分 = 形を貫く線分::生成する(
            大域位置をチャンクの局所座標へ写す(始点, 大域原点)?,
            大域位置をチャンクの局所座標へ写す(終点, 大域原点)?,
        );
        let 問い合わせ = 直方体の線分の問い合わせ::直方体から生成する(&候補.直方体());
        match 問い合わせ.線分が直方体に最初に当たる点を求める(&線分)? {
            線分が直方体に最初に当たる点::直方体に当たらない => Ok(None),
            線分が直方体に最初に当たる点::直方体に当たる(当たり) => Ok(Some(線分と建物の当たり::生成する(
                当たり.交差時刻(),
                局所座標の位置を大域へ写す(当たり.交差位置(), 大域原点),
                局所座標の方向を世界へ写す(当たり.接触面の単位法線())?,
                建物の子形状の所在::生成する(候補.チャンク座標(), 候補.衝突対象の安定識別子(), 候補.子形状識別子()),
                当たり.当たった特徴(),
            ))),
        }
    }
}
