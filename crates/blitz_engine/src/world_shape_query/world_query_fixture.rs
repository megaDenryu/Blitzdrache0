//! 地形と建物の両方への問い合わせの反証が共有する材料。地形の高さ場と、建物を1棟だけ置いた形状の保管と、
//! その2つから問い合わせを組む入口を持つ。
//!
//! 地形は`height_field_tests`の検査用の高さ場をそのまま使う。東10メートルから14メートル・南マイナス20メートル
//! からマイナス18メートルに広がり、東へ1メートルで0.5メートル・南へ1メートルで2メートル上がる1枚の平面である。
//! したがって東11メートル・南マイナス19メートルの地表高さは3.5メートルである。
//!
//! 建物はチャンク(0, -1)へ置く。チャンクの一辺を64メートルにすると、そのチャンクの区画の原点は
//! 東0メートル・南マイナス64メートルであり、東11メートル・南マイナス19メートルの点は局所座標で
//! 東11メートル・南45メートルになる。

use blitz_collision::shape::{任意姿勢の直方体, 直方体の軸ごとの半分の長さ};
use blitz_math::{クォータニオン, メートル, ローカル, 位置, 大域メートル, 大域ワールド位置};

use crate::height_field::height_field_tests::検査用の高さ場を作る;
use crate::height_field::高さ場の読み口;
use crate::static_shape::index::静的世界の候補の選別;
use crate::static_shape::{
    チャンクごとの静的物理形状の保管, チャンクの静的物理形状, 子形状識別子, 衝突対象の子形状, 衝突対象の安定識別子, 静的な衝突対象,
};
use crate::{チャンク一辺, チャンク座標};

use super::query::世界の形への問い合わせ;

/// 建物を置く試験のチャンク。区画の原点は東0メートル・南マイナス64メートルである。
pub(super) const 建物を置くチャンク: チャンク座標 = チャンク座標::生成する(0, -1);

pub(super) fn 大域位置(東: f64, 天頂: f64, 南: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(東), 大域メートル::生成する(天頂), 大域メートル::生成する(南))
}

pub(super) fn 地形を持つ読み口() -> 高さ場の読み口 {
    高さ場の読み口::高さ場を持つ世界(検査用の高さ場を作る())
}

pub(super) fn 地形を持たない読み口() -> 高さ場の読み口 {
    高さ場の読み口::高さ場を持たない世界
}

/// チャンクの局所座標で指定した中心と半分の長さの箱を1つだけ持つ保管。綴りは1棟ぶんで足りる。
pub(super) fn 箱を1つ置いた保管(中心: [f32; 3], 半分: [f32; 3]) -> チャンクごとの静的物理形状の保管 {
    let mut 保管 = チャンクごとの静的物理形状の保管::空を作る();
    let 形状 = match チャンクの静的物理形状::衝突対象一覧から生成する(vec![衝突対象を作る(中心, 半分)]) {
        Ok(形状) => 形状,
        Err(誤り) => panic!("試験用のチャンクの形状を作れなかった: {誤り}"),
    };
    保管.載せる(建物を置くチャンク, 形状);
    保管
}

pub(super) fn 問い合わせを組む<'世界>(
    読み口: &'世界 高さ場の読み口,
    保管: &'世界 チャンクごとの静的物理形状の保管,
) -> 世界の形への問い合わせ<'世界> {
    let 一辺 = match チャンク一辺::生成する(64.0) {
        Ok(一辺) => 一辺,
        Err(誤り) => panic!("試験用のチャンクの一辺を作れなかった: {誤り}"),
    };
    match 静的世界の候補の選別::保管とチャンクの一辺から生成する(保管, 一辺) {
        Ok(選別) => 世界の形への問い合わせ::生成する(読み口, 選別),
        Err(誤り) => panic!("試験用の候補の選別を作れなかった: {誤り}"),
    }
}

fn 衝突対象を作る(中心: [f32; 3], 半分: [f32; 3]) -> 静的な衝突対象 {
    let 位置 = 位置::生成する(メートル::生成する(中心[0]), メートル::生成する(中心[1]), メートル::生成する(中心[2]));
    let (Ok(半分の長さ), Ok(綴り)) = (
        直方体の軸ごとの半分の長さ::生成する(半分.map(メートル::生成する)),
        衝突対象の安定識別子::生成する("試験の建物"),
    ) else {
        panic!("試験用の半分の長さか安定識別子を作れなかった");
    };
    let Ok(直方体) = 任意姿勢の直方体::生成する(位置, クォータニオン::<ローカル, ローカル>::恒等(), 半分の長さ)
    else {
        panic!("試験用の直方体を作れなかった");
    };
    let 子形状 = 衝突対象の子形状::識別子と直方体から生成する(子形状識別子::番号から生成する(0), 直方体);
    match 静的な衝突対象::安定識別子と子形状一覧から生成する(綴り, vec![子形状]) {
        Ok(対象) => 対象,
        Err(誤り) => panic!("試験用の衝突対象を作れなかった: {誤り}"),
    }
}
