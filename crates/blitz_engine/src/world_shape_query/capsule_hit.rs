//! 掃引したカプセルが最初に触れる世界の形。線分の当たりと同じく、地形に触れる枝と建物に触れる枝を分ける。
//! 触れた相手の種別によって答えが持てる事実が違うためである。

use crate::height_field::カプセルと地表の接触;

use super::building_contact::カプセルと建物の接触;

/// 掃引したカプセルが最初に触れる世界の形。何にも触れない枝と、地形に触れる枝と、建物に触れる枝の3つである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 掃引したカプセルが最初に触れる世界の形<'形状> {
    /// 変位の全体を動いても地形にも建物にも触れなかった。
    何にも触れない,
    /// 地形の地表に最初に触れた。
    地形に触れる(カプセルと地表の接触),
    /// 建物の子形状に最初に触れた。
    建物に触れる(カプセルと建物の接触<'形状>),
}
