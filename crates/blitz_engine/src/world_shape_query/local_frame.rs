//! 大域ワールドの座標と、チャンクの区画の原点を基準にした形の局所座標の写し合わせ。
//!
//! この写しを世界の側が持つのは、衝突数学層が世界の原点もチャンクの区画も知らないためである。
//!
//! 丸めがどこで入るか。位置の写しは倍精度の減算1回であり、絶対誤差は大域の座標の大きさに比例する
//! (世界の原点から10の5乗メートル離れた場所で10のマイナス11乗メートルの程度)。この誤差が当たり判定の
//! 誤差になる。変位と向きの写しには丸めが入らない。チャンクの区画は平行移動だけで大域と結ばれており、
//! 軸の向きも縮尺も同じだからである。単位方向を単精度のまま受け渡すのも同じ理由で丸めを通さない。

use blitz_collision::shape::{形の局所座標の位置, 形の局所座標の変位, 形の局所座標の生成エラー};
use blitz_math::{ローカル, ワールド, 変位, 大域メートル, 大域ワールド位置, 方向, 方向エラー};

pub(super) fn 大域位置をチャンクの局所座標へ写す(
    位置: 大域ワールド位置,
    チャンクの大域原点: 大域ワールド位置,
) -> Result<形の局所座標の位置, 形の局所座標の生成エラー> {
    形の局所座標の位置::生成する(
        位置.x().値() - チャンクの大域原点.x().値(),
        位置.y().値() - チャンクの大域原点.y().値(),
        位置.z().値() - チャンクの大域原点.z().値(),
    )
}

pub(super) fn 局所座標の位置を大域へ写す(
    位置: 形の局所座標の位置, チャンクの大域原点: 大域ワールド位置
) -> 大域ワールド位置 {
    大域ワールド位置::生成する(
        大域メートル::生成する(位置.xのメートル() + チャンクの大域原点.x().値()),
        大域メートル::生成する(位置.yのメートル() + チャンクの大域原点.y().値()),
        大域メートル::生成する(位置.zのメートル() + チャンクの大域原点.z().値()),
    )
}

pub(super) fn 世界の変位を局所座標の変位へ写す(
    変位: 変位<ワールド>,
) -> Result<形の局所座標の変位, 形の局所座標の生成エラー> {
    形の局所座標の変位::生成する(f64::from(変位.x().値()), f64::from(変位.y().値()), f64::from(変位.z().値()))
}

pub(super) fn 局所座標の方向を世界へ写す(向き: 方向<ローカル>) -> Result<方向<ワールド>, 方向エラー> {
    方向::生成する(向き.x(), 向き.y(), 向き.z())
}
