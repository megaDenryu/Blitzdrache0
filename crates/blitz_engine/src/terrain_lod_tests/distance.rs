//! 距離とヒステリシスの検査。境界値ちょうど・帯の内側での往復・帯を越えた前後の段を確かめる。

use blitz_render::地形詳細段;

use super::fixture::{ヒステリシス幅, 単独の段, 基準距離, 視点, 選択器を作る};
use crate::チャンク座標;

#[test]
fn 初回は基準距離の床関数で段が決まる() {
    let 座標 = チャンク座標::生成する(0, 0);
    // 原点チャンクの東端は100メートルであるため、視点のXから100を引いた値が距離になる。
    for (視点x, 期待段) in [(150.0, 0), (300.0, 1), (500.0, 2), (700.0, 3), (900.0, 4), (2000.0, 4)] {
        let mut 選択器 = 選択器を作る();
        let mut 受け皿 = Vec::new();
        選択器.選択する(視点(視点x), &[座標], &mut 受け皿);
        assert_eq!(受け皿[0].1, 地形詳細段::番号から生成する(期待段), "視点X={視点x}");
    }
}

#[test]
fn 距離が基準距離ちょうどなら初回は1段粗い側になる() {
    let mut 選択器 = 選択器を作る();
    assert_eq!(単独の段(&mut 選択器, 100.0 + 基準距離), 地形詳細段::番号から生成する(1));
}

#[test]
fn ヒステリシス帯の内側では前回の段を保つ() {
    let 帯の内側 = [基準距離 - ヒステリシス幅 + 1.0, 基準距離, 基準距離 + ヒステリシス幅 - 1.0];
    let mut 細かいまま = 選択器を作る();
    assert_eq!(単独の段(&mut 細かいまま, 100.0 + 基準距離 - ヒステリシス幅 - 1.0), 地形詳細段::最詳細());
    for 距離 in 帯の内側 {
        assert_eq!(単独の段(&mut 細かいまま, 100.0 + 距離), 地形詳細段::最詳細(), "距離{距離}で段0を保つ");
    }

    let mut 粗いまま = 選択器を作る();
    assert_eq!(
        単独の段(&mut 粗いまま, 100.0 + 基準距離 + ヒステリシス幅 + 1.0),
        地形詳細段::番号から生成する(1)
    );
    for 距離 in 帯の内側 {
        assert_eq!(
            単独の段(&mut 粗いまま, 100.0 + 距離),
            地形詳細段::番号から生成する(1),
            "距離{距離}で段1を保つ"
        );
    }
}

#[test]
fn 帯を越えると粗い側へ進み戻ると細かい側へ戻る() {
    let mut 選択器 = 選択器を作る();
    assert_eq!(単独の段(&mut 選択器, 100.0), 地形詳細段::最詳細());
    assert_eq!(
        単独の段(&mut 選択器, 100.0 + 基準距離 + ヒステリシス幅 + 0.5),
        地形詳細段::番号から生成する(1)
    );
    assert_eq!(単独の段(&mut 選択器, 100.0 + 基準距離 - ヒステリシス幅 - 0.5), 地形詳細段::最詳細());
}
