//! 選択の検査が共通して使う設定と視点。基準距離200メートル・ヒステリシス幅10メートル・最粗段4という本番と同じ値を持つ。

use blitz_math::{大域メートル, 大域ワールド位置};
use blitz_render::地形詳細段;

use crate::{チャンク座標, 地形LOD選択器, 地形LOD選択設定};

pub(super) const 基準距離: f64 = 200.0;
pub(super) const ヒステリシス幅: f64 = 10.0;
pub(super) const 一辺: f64 = 100.0;

fn 設定を作る() -> 地形LOD選択設定 {
    地形LOD選択設定::生成する(
        大域メートル::生成する(基準距離),
        大域メートル::生成する(ヒステリシス幅),
        地形詳細段::番号から生成する(4),
    )
    .unwrap()
}

pub(super) fn 選択器を作る() -> 地形LOD選択器 {
    地形LOD選択器::生成する(設定を作る(), 大域メートル::生成する(一辺)).unwrap()
}

/// X方向へ`x`メートルの位置。Zは0であり、原点チャンクは[0,100]×[0,100]を占める。
pub(super) fn 視点(x: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(x), 大域メートル::生成する(0.0), 大域メートル::生成する(0.0))
}

/// 1チャンクだけを常駐させて段を引く。隣接が1つも常駐しないため緩和は働かない。
pub(super) fn 単独の段(選択器: &mut 地形LOD選択器, x: f64) -> 地形詳細段 {
    let mut 受け皿 = Vec::new();
    選択器.選択する(視点(x), &[チャンク座標::生成する(0, 0)], &mut 受け皿);
    受け皿[0].1
}
