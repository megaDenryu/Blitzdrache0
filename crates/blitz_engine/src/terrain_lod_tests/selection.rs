//! 常駐集合に対する選択の検査。緩和を通した隣接差・非常駐隣接の無視・受け皿の並びを確かめる。

use blitz_math::大域メートル;
use blitz_render::地形詳細段;

use super::fixture::{一辺, 視点, 選択器を作る};
use crate::{チャンク座標, 地形LOD選択器, 地形LOD選択設定};

/// 基準距離を格子の一辺より小さくすると、隣り合うチャンクの距離差が1段を超える。緩和を通っていなければこの並びは段差2以上のまま残る。
#[test]
fn 選択は緩和を通して隣接差を1以下にする() {
    let 設定 = 地形LOD選択設定::生成する(大域メートル::生成する(40.0), 大域メートル::生成する(1.0), 地形詳細段::番号から生成する(4)).unwrap();
    let mut 選択器 = 地形LOD選択器::生成する(設定, 大域メートル::生成する(一辺)).unwrap();
    let 常駐: Vec<チャンク座標> = (0..5).map(|x| チャンク座標::生成する(x, 0)).collect();
    let mut 受け皿 = Vec::new();
    選択器.選択する(視点(50.0), &常駐, &mut 受け皿);
    let 段一覧: Vec<u8> = 受け皿.iter().map(|(_, 段)| 段.番号()).collect();
    assert_eq!(段一覧[0], 0, "視点を含むチャンクは最詳細である");
    for 位置 in 1..段一覧.len() {
        let 差 = i32::from(段一覧[位置]) - i32::from(段一覧[位置 - 1]);
        assert!(差.abs() <= 1, "隣接する段の差が1を超えた: {段一覧:?}");
    }
    assert_eq!(段一覧.last().copied(), Some(4), "最も遠いチャンクは最も粗い段になる");
}

#[test]
fn 常駐しない隣接は緩和の制約に数えない() {
    let mut 選択器 = 選択器を作る();
    let mut 受け皿 = Vec::new();
    // 遠い1チャンクだけを常駐させる。隣接が1つも常駐しないため、距離で決まった粗い段がそのまま残る。
    let 遠い座標 = チャンク座標::生成する(9, 0);
    選択器.選択する(視点(0.0), &[遠い座標], &mut 受け皿);
    assert_eq!(受け皿, vec![(遠い座標, 地形詳細段::番号から生成する(4))]);
}

#[test]
fn 受け皿は座標の辞書順に並ぶ() {
    let mut 選択器 = 選択器を作る();
    let mut 受け皿 = Vec::new();
    let 常駐 = [
        チャンク座標::生成する(1, -1),
        チャンク座標::生成する(0, 2),
        チャンク座標::生成する(0, -3),
        チャンク座標::生成する(-1, 5),
    ];
    選択器.選択する(視点(50.0), &常駐, &mut 受け皿);
    let 並び: Vec<(i32, i32)> = 受け皿.iter().map(|(座標, _)| (座標.x(), 座標.z())).collect();
    assert_eq!(並び, vec![(-1, 5), (0, -3), (0, 2), (1, -1)]);
}
