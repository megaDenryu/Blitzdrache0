use crate::{
    streaming_budget_tests::要求を作る, ストリーミングメモリ量, ストリーミング予算, チャンク予算候補, 予算判定
};

#[test]
fn バイト数の加算オーバーフローをram超過として縮退する() {
    let 要求 = 要求を作る()[0];
    let 候補 = [チャンク予算候補::生成する(
        要求,
        ストリーミングメモリ量::生成する(u64::MAX, 1),
    )];
    let Ok(予算) = ストリーミング予算::生成する(ストリーミングメモリ量::生成する(u64::MAX, 10)) else {
        panic!("試験用予算を作れなかった");
    };
    let Ok(結果) = 予算.適用する(ストリーミングメモリ量::生成する(1, 0), &候補) else {
        panic!("オーバーフロー候補へ予算を適用できなかった");
    };
    assert!(matches!(
        結果.判定(),
        予算判定::縮退 {
            ram超過: true,
            vram超過: false,
            ..
        }
    ));
}
