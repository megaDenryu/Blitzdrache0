//! 試験用チャンク世界の実体を所有する。ディスク上の生成物を書き、それを指すカタログとチャンク目録を組み立て、試験の終わりに生成物を消すまでを担当する。
//! 調停をどう動かすかは`streaming_coordinator_fixture`が持ち、ここは世界の中身だけを知る。

use std::path::PathBuf;

use crate::asset::runtime_scene_tests::静的シーンを作る;
use crate::{
    アセットID, アセットメタデータ, カタログ, シーンを実行時形式へ格納する, チャンク座標, チャンク目録
};

/// 検証用の板1枚と同じ構成。4頂点48バイト、6インデックス4バイト、1画素テクスチャ4バイトで見積は220バイトになる。
pub(super) fn 試験メタデータ() -> アセットメタデータ {
    アセットメタデータ {
        頂点数: 4,
        インデックス数: 6,
        テクスチャバイト数: 4,
        個体数: 0,
    }
}

/// 生成物のベースカラー画素。内容の入れ替わりを見る試験だけが別の画素を渡す。
fn 既定画素() -> Vec<u8> {
    vec![10, 20, 30, 255]
}

pub(super) fn 世界を作る(名前: &str, 座標一覧: &[(i32, i32)]) -> (Vec<PathBuf>, カタログ, チャンク目録) {
    let (パス一覧, カタログ) = 生成物とカタログを作る(名前, "v1", 座標一覧, 既定画素());
    let mut 目録 = チャンク目録::空を作る();
    for (x, z) in 座標一覧 {
        let Ok(id) = アセットID::生成する(&名称を作る(名前, *x, *z)) else {
            panic!("試験用アセットIDを作れなかった");
        };
        if let Err(誤り) = 目録.登録する(チャンク座標::生成する(*x, *z), id) {
            panic!("試験用目録へ登録できなかった: {誤り}");
        }
    }
    (パス一覧, カタログ, 目録)
}

/// 同じアセットIDを別の内容の生成物へ向けた2つ目のカタログ。1つ目の生成物を上書きしないため、
/// 先に投入した読込は古い内容のまま完了する。ホットリロードでアセットの中身が入れ替わった状態を、
/// 同じ目録のまま渡すカタログを差し替えることで作る。
pub(super) fn 内容を変えたカタログを作る(名前: &str, 座標一覧: &[(i32, i32)], 画素: Vec<u8>) -> (Vec<PathBuf>, カタログ) {
    生成物とカタログを作る(名前, "v2", 座標一覧, 画素)
}

/// 同じアセットIDを存在しない生成物へ向けたカタログ。ファイルを書かないため読込は必ず失敗する。
/// リセット前に投入した読込が失敗として完了する状況を、決定的に作るための道具である。
pub(super) fn 存在しない生成物のカタログを作る(名前: &str, 座標一覧: &[(i32, i32)]) -> カタログ {
    let mut カタログ = カタログ::空を作る();
    for (x, z) in 座標一覧 {
        let 名称 = 名称を作る(名前, *x, *z);
        let Ok(id) = アセットID::生成する(&名称) else {
            panic!("試験用アセットIDを作れなかった");
        };
        カタログ.詳細を登録する(
            id,
            PathBuf::from("target").join(format!("{名称}_missing.blitzasset")),
            Vec::new(),
            試験メタデータ(),
        );
    }
    カタログ
}

/// ファイル名にプロセスIDを混ぜ、並行する試験どうしが同じ生成物を奪い合わないようにする。
fn 名称を作る(名前: &str, x: i32, z: i32) -> String {
    format!("{名前}_x{x}_z{z}_{}", std::process::id())
}

/// 指定した画素の実行時シーンを座標ごとに書き、同じアセットIDで参照できるカタログを組み立てる。
/// `版名`が分けるのはファイル名だけであり、アセットIDは変えない。目録を組み直さずに内容だけを差し替えられるようにするためである。
fn 生成物とカタログを作る(名前: &str, 版名: &str, 座標一覧: &[(i32, i32)], 画素: Vec<u8>) -> (Vec<PathBuf>, カタログ) {
    let Ok(バイト列) = シーンを実行時形式へ格納する(&静的シーンを作る(画素, 0.2)) else {
        panic!("試験用チャンクシーンを格納できなかった");
    };
    let mut カタログ = カタログ::空を作る();
    let mut パス一覧 = Vec::new();
    for (x, z) in 座標一覧 {
        let 名称 = 名称を作る(名前, *x, *z);
        let パス = PathBuf::from("target").join(format!("{名称}_{版名}.blitzasset"));
        if let Err(誤り) = std::fs::write(&パス, &バイト列) {
            panic!("試験用チャンク生成物を書けなかった: {誤り}");
        }
        let Ok(id) = アセットID::生成する(&名称) else {
            panic!("試験用アセットIDを作れなかった");
        };
        カタログ.詳細を登録する(id, パス.clone(), Vec::new(), 試験メタデータ());
        パス一覧.push(パス);
    }
    (パス一覧, カタログ)
}

pub(super) fn 後始末する(パス一覧: &[PathBuf]) {
    for パス in パス一覧 {
        assert!(std::fs::remove_file(パス).is_ok());
    }
}
