//! 段を分ける距離とヒステリシスの帯。基準距離とヒステリシス幅を検証して保持し、距離から段番号を返す。
//! ヒステリシス幅を基準距離の半分未満に限るのは、幅が半分以上だと隣り合う2つの境界の帯が重なり、
//! 同じ距離が2段ぶん先の切替条件を同時に満たしうるためである。
//!
//! 粗い側へ切り替えるのは距離が境界にヒステリシス幅を足した値を超えたとき、細かい側へ戻すのは境界から
//! ヒステリシス幅を引いた値を下回ったときである。帯の内側では前回の段を保つため、境界をまたぐ往復で段が毎フレーム入れ替わらない。

use super::error::段閾値エラー;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 段閾値帯 {
    基準距離: f64,
    ヒステリシス幅: f64,
}

impl 段閾値帯 {
    pub fn 生成する(基準距離: f64, ヒステリシス幅: f64) -> Result<Self, 段閾値エラー> {
        if !基準距離.is_finite() || 基準距離 <= 0.0 {
            return Err(段閾値エラー::基準距離不正);
        }
        if !ヒステリシス幅.is_finite() || ヒステリシス幅 < 0.0 {
            return Err(段閾値エラー::ヒステリシス幅不正);
        }
        if ヒステリシス幅 * 2.0 >= 基準距離 {
            return Err(段閾値エラー::ヒステリシス幅過大);
        }
        Ok(Self {
            基準距離, ヒステリシス幅
        })
    }

    /// 段番号nと段番号n+1を分ける距離。段番号0と1の境界が基準距離そのものである。
    pub fn 境界距離(self, 細かい段番号: u8) -> f64 {
        self.基準距離 * f64::from(u16::from(細かい段番号) + 1)
    }

    /// ヒステリシスを使わない初回の段番号。距離を基準距離で割った商を最も粗い段で頭打ちにした値と一致する。
    /// 商を整数へ丸めず境界と順に比べるのは、段数が数段であり比較の回数が丸めの縮小変換より短くて済むためである。
    pub fn 初回の段番号(self, 距離: f64, 最粗段番号: u8) -> u8 {
        let mut 段番号 = 0u8;
        while 段番号 < 最粗段番号 && 距離 >= self.境界距離(段番号) {
            段番号 += 1;
        }
        段番号
    }

    /// 前回の段番号があるときの今回の段番号。無ければ初回の段番号を返す。
    pub fn 段番号を決める(self, 前回: Option<u8>, 距離: f64, 最粗段番号: u8) -> u8 {
        let Some(前回) = 前回 else {
            return self.初回の段番号(距離, 最粗段番号);
        };
        self.細かい側へ戻す(self.粗い側へ進める(前回, 距離, 最粗段番号), 距離)
    }

    fn 粗い側へ進める(self, 前回: u8, 距離: f64, 最粗段番号: u8) -> u8 {
        let mut 段番号 = 前回;
        while 段番号 < 最粗段番号 && 距離 > self.境界距離(段番号) + self.ヒステリシス幅 {
            段番号 += 1;
        }
        段番号
    }

    fn 細かい側へ戻す(self, 前回: u8, 距離: f64) -> u8 {
        let mut 段番号 = 前回;
        while let Some(細かい段番号) = 段番号.checked_sub(1) {
            if 距離 >= self.境界距離(細かい段番号) - self.ヒステリシス幅 {
                break;
            }
            段番号 = 細かい段番号;
        }
        段番号
    }
}
