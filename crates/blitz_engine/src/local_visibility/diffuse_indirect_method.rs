//! 世界が宣言する拡散間接照度の作り方。
//!
//! 世界の間接照明方針・露出方式と別の型にするのは、3つが独立の軸だからである。局所可視性補正は拡散間接照度へ
//! 掛かる係数であって、照度そのものの供給元でも画の完成の段でもない。既定は環境のみであり、
//! 局所可視性補正を選ぶ世界だけがもう一方の枝を持つ。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 拡散間接方式 {
    /// 間接照明の供給元が答えた拡散間接照度をそのまま使う。
    環境のみ,
    /// 同じ拡散間接照度へ、深度から求めた局所可視度を掛ける。
    局所可視性補正付き環境,
}
