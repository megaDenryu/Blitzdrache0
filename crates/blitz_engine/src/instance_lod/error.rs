//! 個体別LODの選択を組み立てるときに拒む理由。設定値の検証と、原型の段数の検証の2つが失敗しうる。

use thiserror::Error;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 個体LODエラー {
    #[error("基準距離が正の有限メートルでない")]
    基準距離不正,
    #[error("ヒステリシス幅が0以上の有限メートルでない")]
    ヒステリシス幅不正,
    #[error("ヒステリシス幅が基準距離の半分以上である")]
    ヒステリシス幅過大,
    #[error("原型のメッシュLOD列が空である")]
    段数なし,
    /// 段番号はu8で持つため、256段を超える原型は段の順序を表せない。
    #[error("原型のメッシュLOD段数{段数}が段番号の上限を超えた")]
    段数過大 { 段数: usize },
}
