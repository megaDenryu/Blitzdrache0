//! 1つのインスタンス群が持つ個体別の段の記憶。束の読込時に個体数ぶんを一度だけ確保し、以後は毎フレーム書き換えるだけである。
//! 毎フレーム確保しないことが「LOD切替はディスクI/Oも束の再読込もGPU再確保も起こさない」という不変条件の一部である。
//!
//! 前回の段を`Option`で持つのは、まだ一度も選んでいない個体を「たまたま最詳細段になった個体」と区別するためである。
//! 未選択を段番号のマジック値へ密輸すると、その番号の段を実際に選んだ個体が毎フレーム初回扱いになる。
//! 切替回数をこの型が数えるのは、前回の段を知っているのがこの型だけであり、段が振動していないことを
//! 実行の外から見る観測点がここにしか置けないためである。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「個体別LOD」

use blitz_math::メートル;

use super::level::個体詳細段;
use super::settings::個体LOD選択設定;

pub struct 個体別段状態 {
    最粗段: 個体詳細段,
    前回の段一覧: Vec<Option<個体詳細段>>,
    切替回数: u64,
}

impl 個体別段状態 {
    /// 最も粗い段は原型が持つ。原型は生成の時点で段を1つ以上かつ段番号の上限以下しか受け付けないため、
    /// この構築は失敗しない。
    pub fn 生成する(個体数: usize, 最粗段: 個体詳細段) -> Self {
        Self {
            最粗段,
            前回の段一覧: vec![None; 個体数],
            切替回数: 0,
        }
    }

    pub fn 個体数(&self) -> usize {
        self.前回の段一覧.len()
    }

    pub fn 段数(&self) -> usize {
        self.最粗段.添字() + 1
    }

    /// 起動から現在までに段が入れ替わった延べ回数。初回の決定は入れ替わりに数えない。
    pub fn 切替回数(&self) -> u64 {
        self.切替回数
    }

    /// 個体1件の段を距離から決め、次のフレームのために記録する。
    /// 注意: 添字が個体数の外を指すのは、群の可視材料とこの状態が同じ個体数を持つという不変条件が破れた場合だけである。
    pub fn 段を決める(&mut self, 添字: usize, 距離: メートル, 設定: 個体LOD選択設定) -> 個体詳細段 {
        let Some(記憶) = self.前回の段一覧.get_mut(添字) else {
            panic!("個体別段状態の個体数が群の個体数と一致するという不変条件に違反した: 添字{添字}");
        };
        let 前回 = *記憶;
        let 段番号 = 設定
            .帯()
            .段番号を決める(前回.map(個体詳細段::番号), f64::from(距離.値()), self.最粗段.番号());
        let 段 = 個体詳細段::番号から生成する(段番号);
        if 前回.is_some_and(|前回の段| 前回の段 != 段) {
            self.切替回数 += 1;
        }
        *記憶 = Some(段);
        段
    }
}
