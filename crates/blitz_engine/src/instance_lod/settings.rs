//! 個体別LODの選択設定。段を分ける距離の帯だけを持ち、最も粗い段は持たない。
//! 最粗段を持たないのは、それが群ごとの原型が焼いた段数で決まる値であり、世界全体で1つに定まらないためである。
//! 距離をメートルで受け取るのは、判定がカメラ相対空間のf32メートルで行われるためである。

use blitz_math::メートル;

use super::error::個体LODエラー;
use crate::lod_threshold::{段閾値エラー, 段閾値帯};

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 個体LOD選択設定 {
    帯: 段閾値帯,
}

impl 個体LOD選択設定 {
    pub fn 生成する(基準距離: メートル, ヒステリシス幅: メートル) -> Result<Self, 個体LODエラー> {
        let 帯 = 段閾値帯::生成する(f64::from(基準距離.値()), f64::from(ヒステリシス幅.値())).map_err(個体の語彙へ写す)?;
        Ok(Self { 帯 })
    }

    pub(super) fn 帯(self) -> 段閾値帯 {
        self.帯
    }
}

/// 核が拒む理由は地形と個体で共通だが、呼び出し元が受け取るのは個体の語彙のエラーである。
/// 同じ破れを2つの型で表さないため、境界であるここ1箇所で写す。
fn 個体の語彙へ写す(誤り: 段閾値エラー) -> 個体LODエラー {
    match 誤り {
        段閾値エラー::基準距離不正 => 個体LODエラー::基準距離不正,
        段閾値エラー::ヒステリシス幅不正 => 個体LODエラー::ヒステリシス幅不正,
        段閾値エラー::ヒステリシス幅過大 => 個体LODエラー::ヒステリシス幅過大,
    }
}
