use crate::streaming_chunk_world_fixture::{世界を作る, 後始末する, 試験メタデータ};
use crate::streaming_coordinator_fixture::{準備完了を待つ, 起動する, 進める};
use crate::{ストリーミングメモリ量, チャンクメモリ量を見積もる, チャンク座標};

/// 1チャンクのRAM実測バイト数。版付きファイル全体の長さであり見積とは別の量であるため、値を決め打ちせず実際に読んで測る。
/// 試験は並行に走り、世界の名前が生成物のファイル名になるため、呼出しごとに別の名前を渡して同じファイルを奪い合わないようにする。
fn 実測ramバイト数を測る(名前: &str) -> u64 {
    let (パス一覧, カタログ, 目録) = 世界を作る(名前, &[(0, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(100_000, 100_000), 1);
    準備完了を待つ(&mut 調停, &カタログ, 50.0, 1);
    let 実測 = 調停.転送量().ディスク読込バイト数();
    後始末する(&パス一覧);
    実測
}

fn 見積ramバイト数() -> u64 {
    match チャンクメモリ量を見積もる(試験メタデータ()) {
        Ok(見積) => 見積.ramバイト数,
        Err(誤り) => panic!("試験用見積を作れなかった: {誤り}"),
    }
}

/// 見積は版付きファイルの固定部分を数えないため、実測より必ず小さい。この差が読込後の上限超過を生む。
#[test]
fn 読込の実測は見積を上回る() {
    assert!(実測ramバイト数を測る("measured_probe_compare") > 見積ramバイト数());
}

#[test]
fn 一度読んだ座標は再収容の判定に実測を使う() {
    let 実測 = 実測ramバイト数を測る("measured_probe_reentry");
    let 見積 = 見積ramバイト数();
    let (パス一覧, カタログ, 目録) = 世界を作る("measured_reentry", &[(0, 0), (1, 0)]);
    // 見積2件はちょうど収まり、実測1件と見積1件は収まらない上限。実測を覚えていなければ2件目を再び収容してしまう。
    let 上限 = ストリーミングメモリ量::生成する(実測 + 見積 - 1, 100_000);
    let mut 調停 = 起動する(目録, 上限, 1);
    let 初回 = 進める(&mut 調停, &カタログ, 50.0);
    assert_eq!(初回.読込開始一覧(), [チャンク座標::生成する(0, 0), チャンク座標::生成する(1, 0)]);
    準備完了を待つ(&mut 調停, &カタログ, 50.0, 2);

    // 目録に無い遠方へ移ると台帳から記録が消えるが、実測の記憶は残る。
    進める(&mut 調停, &カタログ, 100_050.0);
    assert_eq!(調停.台帳登録数(), 0);
    assert_eq!(調停.実測記憶件数(), 2);

    // 見積のままなら2件とも収容できる上限だが、実測を使うため中心1件だけになる。
    let 再訪 = 進める(&mut 調停, &カタログ, 50.0);
    assert_eq!(再訪.読込開始一覧(), [チャンク座標::生成する(0, 0)]);
    後始末する(&パス一覧);
}
