//! 読込済みチャンクの形の版が、ゲームの読む形の集合が変わる経路のそれぞれで進み、変わらない経路では進まないことの試験。

use crate::streaming_chunk_world_fixture::{世界を作る, 後始末する};
use crate::streaming_coordinator_fixture::{常駐まで進める, 準備完了を待つ, 起動する, 進める};
use crate::{ストリーミングメモリ量, チャンク目録, 読込済みチャンクの形の版};

fn 上限を作る() -> ストリーミングメモリ量 {
    ストリーミングメモリ量::生成する(100_000, 100_000)
}

#[test]
fn 起動直後は最初の版であり読込完了で載るたびに進む() {
    let (パス一覧, カタログ, 目録) = 世界を作る("shape_version_load", &[(0, 0), (1, 0)]);
    let mut 調停 = 起動する(目録, 上限を作る(), 1);
    assert_eq!(調停.読込済みチャンクの形の版(), 読込済みチャンクの形の版::最初を作る());
    準備完了を待つ(&mut 調停, &カタログ, 50.0, 2);
    assert_eq!(調停.読込済みチャンクの形の版(), 読込済みチャンクの形の版::最初を作る().次を作る().次を作る());
    後始末する(&パス一覧);
}

#[test]
fn 形が変わらないフレームでは版が進まない() {
    let (パス一覧, カタログ, 目録) = 世界を作る("shape_version_still", &[(0, 0)]);
    let mut 調停 = 起動する(目録, 上限を作る(), 0);
    常駐まで進める(&mut 調停, &カタログ, 50.0, 1);
    let 版 = 調停.読込済みチャンクの形の版();
    進める(&mut 調停, &カタログ, 50.0);
    assert_eq!(調停.読込済みチャンクの形の版(), 版);
    後始末する(&パス一覧);
}

#[test]
fn リセットと目録の差し替えは保管が空でも版を進める() {
    let (パス一覧, _カタログ, 目録) = 世界を作る("shape_version_reset", &[(0, 0)]);
    let 一辺 = 目録.一辺();
    let mut 調停 = 起動する(目録, 上限を作る(), 0);
    調停.リセットする();
    let リセット後 = 読込済みチャンクの形の版::最初を作る().次を作る();
    assert_eq!(調停.読込済みチャンクの形の版(), リセット後);
    assert!(調停.チャンク目録を差し替える(チャンク目録::空を作る(一辺)).is_ok());
    assert_eq!(調停.読込済みチャンクの形の版(), リセット後.次を作る());
    後始末する(&パス一覧);
}

#[test]
fn 実破棄の報告で形が外れると版が進む() {
    let (パス一覧, カタログ, 目録) = 世界を作る("shape_version_release", &[(0, 0)]);
    let mut 調停 = 起動する(目録, 上限を作る(), 0);
    let 座標一覧 = 常駐まで進める(&mut 調停, &カタログ, 50.0, 1);
    // 目録に無い遠方へ移って解除待ちにしてから、実破棄を報告する。
    進める(&mut 調停, &カタログ, 100_050.0);
    let 解除前 = 調停.読込済みチャンクの形の版();
    for 座標 in 座標一覧 {
        if let Err(誤り) = 調停.gpu資源の解除を報告する(座標) {
            panic!("実破棄を報告できなかった: {誤り}");
        }
    }
    assert_eq!(調停.読込済みチャンクの形の版(), 解除前.次を作る());
    後始末する(&パス一覧);
}

/// 反証: この経路が版を進めないと、GPUへ送る前に捨てたチャンクの形が消えたことを刻みが観測できない。
#[test]
fn 準備済みのcpuデータを捨てると版が進む() {
    let (パス一覧, カタログ, 目録) = 世界を作る("shape_version_cpu_discard", &[(0, 0)]);
    let mut 調停 = 起動する(目録, 上限を作る(), 0);
    準備完了を待つ(&mut 調停, &カタログ, 50.0, 1);
    assert_eq!(調停.静的物理形状を持つチャンク数(), 1);
    let 破棄前 = 調停.読込済みチャンクの形の版();
    // GPU転送へ渡さないまま目録に無い遠方へ移すと、準備済みのCPUデータが同じフレームで捨てられる。
    let 進行 = 進める(&mut 調停, &カタログ, 100_050.0);
    assert_eq!(進行.cpuデータ破棄一覧().len(), 1);
    assert_eq!(調停.静的物理形状を持つチャンク数(), 0);
    assert_eq!(調停.読込済みチャンクの形の版(), 破棄前.次を作る());
    後始末する(&パス一覧);
}
