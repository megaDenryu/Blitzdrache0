//! 試験から見たストリーミング調停の動かし方を所有する。起動、プレイヤー位置を与えた1フレームの前進、準備完了と常駐までの待ち合わせを担当し、
//! 試験本体は段階の順序も待ち方も知らずに呼べる。世界の実体は`streaming_chunk_world_fixture`が持つ。

use std::time::{Duration, Instant};

use blitz_math::{大域メートル, 大域ワールド位置};

use crate::streaming_chunk_world_fixture::{世界を作る, 後始末する, 試験メタデータ};
use crate::{
    カタログ, ストリーミングメモリ量, ストリーミング調停, ストリーミング調停設定, ストリーミング進行, チャンクメモリ量を見積もる, チャンク座標,
    チャンク目録, チャンク読込設定,
};

pub(super) fn 起動する(
    目録: チャンク目録, 上限: ストリーミングメモリ量, 先読み半径: u8
) -> ストリーミング調停 {
    let 設定 = ストリーミング調停設定 {
        先読み半径,
        上限,
        読込: チャンク読込設定::既定値(),
    };
    match ストリーミング調停::起動する(設定, 目録) {
        Ok(調停) => 調停,
        Err(誤り) => panic!("試験用調停を起動できなかった: {誤り}"),
    }
}

/// Zを50メートルに固定し、Xだけを動かしてプレイヤーの所属チャンクを選ぶ。
pub(super) fn 進める(調停: &mut ストリーミング調停, カタログ: &カタログ, x: f64) -> ストリーミング進行 {
    let 位置 = 大域ワールド位置::生成する(大域メートル::生成する(x), 大域メートル::生成する(0.0), 大域メートル::生成する(50.0));
    match 調停.一フレーム進める(位置, カタログ) {
        Ok(進行) => 進行,
        Err(誤り) => panic!("調停を1フレーム進められなかった: {誤り}"),
    }
}

pub(super) fn 準備完了を待つ(
    調停: &mut ストリーミング調停, カタログ: &カタログ, x: f64, 件数: usize
) -> Vec<チャンク座標> {
    let 期限 = Instant::now() + Duration::from_secs(5);
    let mut 累積 = Vec::new();
    while 累積.len() < 件数 {
        assert!(Instant::now() < 期限, "チャンクの準備完了が期限内に揃わなかった");
        累積.extend_from_slice(進める(調停, カタログ, x).準備完了一覧());
    }
    累積
}

/// 1チャンクのカタログ由来の見積量。上限を「何チャンク分」で置く試験がこの値を基準にする。
pub(super) fn 見積量を作る() -> ストリーミングメモリ量 {
    match チャンクメモリ量を見積もる(試験メタデータ()) {
        Ok(見積) => 見積,
        Err(誤り) => panic!("試験用見積を作れなかった: {誤り}"),
    }
}

/// 1チャンクの読込量。版付きファイル全体の長さであり見積とは別の量であるため、値を決め打ちせず実際に読んで測る。
/// 世界の名前が生成物のファイル名になり試験は並行に走るため、呼出しごとに別の名前を渡して同じファイルを奪い合わないようにする。
pub(super) fn 読込バイト数を測る(名前: &str) -> u64 {
    let (パス一覧, カタログ, 目録) = 世界を作る(名前, &[(0, 0)]);
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(100_000, 100_000), 1);
    準備完了を待つ(&mut 調停, &カタログ, 50.0, 1);
    let 観測 = 調停.転送量().ディスク読込バイト数();
    後始末する(&パス一覧);
    観測
}

/// 準備完了した座標をGPU受け渡しの2手続きへ通して常駐まで進める。退避の対象になるのは常駐チャンクだけであるため、退避の試験はここを通る。
pub(super) fn 常駐まで進める(
    調停: &mut ストリーミング調停, カタログ: &カタログ, x: f64, 件数: usize
) -> Vec<チャンク座標> {
    let 座標一覧 = 準備完了を待つ(調停, カタログ, x, 件数);
    for 座標 in &座標一覧 {
        let Ok(Some(_シーン)) = 調停.gpu転送のためにシーンデータを取り出す(*座標) else {
            panic!("準備済みチャンクのシーンデータを取り出せなかった");
        };
        if let Err(誤り) = 調停.gpu転送の完了を報告する(*座標) {
            panic!("GPU転送の完了を報告できなかった: {誤り}");
        }
    }
    座標一覧
}
