//! ストリーミング調停の試験が使うチャンク世界の足場を所有する。ディスク上の生成物、それを指すカタログと目録の生成、
//! 調停の起動、1フレームの前進、後始末までを担当し、試験本体は組み立て手順を知らずに呼べる。

use std::path::PathBuf;
use std::time::{Duration, Instant};

use blitz_math::{大域メートル, 大域ワールド位置};

use crate::asset::runtime_scene_tests::静的シーンを作る;
use crate::{
    アセットID, アセットメタデータ, カタログ, シーンを実行時形式へ格納する, ストリーミングメモリ量, ストリーミング調停, ストリーミング調停設定,
    ストリーミング進行, チャンク座標, チャンク目録,
};

pub(super) fn 起動する(目録: チャンク目録, 上限: ストリーミングメモリ量) -> ストリーミング調停 {
    let 設定 = ストリーミング調停設定 {
        一辺: 大域メートル::生成する(100.0),
        先読み半径: 1,
        上限,
    };
    match ストリーミング調停::起動する(設定, 目録) {
        Ok(調停) => 調停,
        Err(誤り) => panic!("試験用調停を起動できなかった: {誤り}"),
    }
}

/// Zを50メートルに固定し、Xだけを動かしてプレイヤーの所属チャンクを選ぶ。
pub(super) fn 進める(調停: &mut ストリーミング調停, カタログ: &カタログ, x: f64) -> ストリーミング進行 {
    let 位置 = 大域ワールド位置::生成する(大域メートル::生成する(x), 大域メートル::生成する(0.0), 大域メートル::生成する(50.0));
    match 調停.一フレーム進める(位置, カタログ) {
        Ok(進行) => 進行,
        Err(誤り) => panic!("調停を1フレーム進められなかった: {誤り}"),
    }
}

pub(super) fn 準備完了を待つ(
    調停: &mut ストリーミング調停, カタログ: &カタログ, x: f64, 件数: usize
) -> Vec<チャンク座標> {
    let 期限 = Instant::now() + Duration::from_secs(5);
    let mut 累積 = Vec::new();
    while 累積.len() < 件数 {
        assert!(Instant::now() < 期限, "チャンクの準備完了が期限内に揃わなかった");
        累積.extend_from_slice(進める(調停, カタログ, x).準備完了一覧());
    }
    累積
}

/// 検証用の板1枚と同じ構成のメタデータを付ける。4頂点48バイト、6インデックス4バイト、1画素テクスチャ4バイトで見積は220バイトになる。
pub(super) fn 世界を作る(名前: &str, 座標一覧: &[(i32, i32)]) -> (Vec<PathBuf>, カタログ, チャンク目録) {
    let メタデータ = アセットメタデータ {
        頂点数: 4,
        インデックス数: 6,
        テクスチャバイト数: 4,
    };
    let Ok(バイト列) = シーンを実行時形式へ格納する(&静的シーンを作る(vec![10, 20, 30, 255], 0.2)) else {
        panic!("試験用チャンクシーンを格納できなかった");
    };
    let mut カタログ = カタログ::空を作る();
    let mut 目録 = チャンク目録::空を作る();
    let mut パス一覧 = Vec::new();
    for (x, z) in 座標一覧 {
        let 名称 = format!("{名前}_x{x}_z{z}_{}", std::process::id());
        let パス = PathBuf::from("target").join(format!("{名称}.blitzasset"));
        if let Err(誤り) = std::fs::write(&パス, &バイト列) {
            panic!("試験用チャンク生成物を書けなかった: {誤り}");
        }
        let Ok(id) = アセットID::生成する(&名称) else {
            panic!("試験用アセットIDを作れなかった");
        };
        カタログ.詳細を登録する(id.clone(), パス.clone(), Vec::new(), メタデータ);
        if let Err(誤り) = 目録.登録する(チャンク座標::生成する(*x, *z), id) {
            panic!("試験用目録へ登録できなかった: {誤り}");
        }
        パス一覧.push(パス);
    }
    (パス一覧, カタログ, 目録)
}

pub(super) fn 後始末する(パス一覧: &[PathBuf]) {
    for パス in パス一覧 {
        assert!(std::fs::remove_file(パス).is_ok());
    }
}
