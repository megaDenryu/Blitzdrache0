//! シーン既定のライト方針を組み立て、レンダラーの安全な入力へ翻訳する。

use blitz_math::{ビュー, メートル, ワールド, 位置, 光源クリップ, 変換};
use blitz_render::{
    ライティング入力, ライティング入力エラー, 光強度, 光色, 影入力, 方向光入力, 点光源入力, 環境光係数
};

pub fn 既定ライティングを作る(有効: bool) -> ライティング入力 {
    let 白 = 確定値(光色::生成する(1.0, 1.0, 1.0));
    let 方向光 = 確定値(方向光入力::生成する(-0.4, -1.0, -0.6, 白, 確定値(光強度::生成する(3.0))));
    let 点光源 = 確定値(点光源入力::生成する(
        位置::生成する(メートル::生成する(2.0), メートル::生成する(2.0), メートル::生成する(2.0)),
        白,
        確定値(光強度::生成する(10.0)),
    ));
    ライティング入力::生成する(
        方向光,
        点光源,
        確定値(環境光係数::生成する(0.03)),
        確定値(影入力::生成する(ライトビュー射影を作る(方向光))),
        有効,
    )
}

fn ライトビュー射影を作る(方向光: 方向光入力) -> 変換<ワールド, 光源クリップ> {
    let 光源位置 = 方向光.逆方向へ離れた位置(メートル::生成する(10.0));
    let 原点 = 位置::生成する(メートル::生成する(0.0), メートル::生成する(0.0), メートル::生成する(0.0));
    let ビュー変換: 変換<ワールド, ビュー> = 変換::注視(光源位置, 原点);
    let 投影: 変換<ビュー, 光源クリップ> = 変換::正射影(
        メートル::生成する(4.0),
        メートル::生成する(4.0),
        メートル::生成する(0.1),
        メートル::生成する(20.0),
    );
    ビュー変換.合成する(投影)
}

fn 確定値<T>(結果: Result<T, ライティング入力エラー>) -> T {
    結果.unwrap_or_else(|誤り| panic!("既定ライティング定数が不正だった: {誤り}"))
}
