//! シーン既定のライト方針を組み立て、レンダラーの安全な入力へ翻訳する。
//! 影は焼いた行列でなく再構築パラメータで渡す。カメラ相対フレームでの組み立てはレンダラーが毎フレーム行う。

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};
