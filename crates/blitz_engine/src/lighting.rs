mod lighting_tests;

pub use from_sky_state::天空状態をライティングへ写す;

/// 影の正射影が見る範囲の中心。既定シーンは原点近傍に置くため世界原点を注視する。
const 影注視点メートル: f64 = 0.0;
/// 注視点から方向光の逆向きへ光源を離す距離。
const 影光源距離: f32 = 10.0;
/// 既定の点光源の影響半径。減衰の窓を掛ける段でこの光の絵が動かないことを、次の見積りで確かめて置いた値である。
/// 強度10のこの光の寄与は距離100メートルで0.001まで落ち、8ビットの符号値の刻み(255分の1)を下回る。
/// 半径1500メートルなら距離100メートルでの窓の1からの外れが`2 × (100 / 1500)の4乗`すなわちおよそ25000分の1であり、
/// その刻みより2桁小さい(参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断b」)。
const 既定の影響半径メートル: f32 = 1500.0;

/// `大域ずらし量`は世界全体へ加える平行移動である。光源と影の基準を対象・カメラと同じだけずらすため、原点移動不変性の検査が成立する。
pub fn 既定ライティングを作る(有効: bool, 大域ずらし量: 大域ワールド位置) -> ライティング入力 {
    let 白 = 定数の検証結果から値を取り出す(光色::生成する(1.0, 1.0, 1.0));
    let 方向光 = 定数の検証結果から値を取り出す(方向光入力::生成する(
        -0.4,
        -1.0,
        -0.6,
        白,
        定数の検証結果から値を取り出す(光強度::生成する(3.0)),
    ));
    let 点光源位置 = 大域位置を作る(2.0, 2.0, 2.0).平行移動する(大域ずらし量);
    let 点光源 = 定数の検証結果から値を取り出す(点光源入力::生成する(
        点光源位置,
        白,
        定数の検証結果から値を取り出す(光強度::生成する(10.0)),
        既定の影響半径を作る(),
        点光源の可視性::影なし,
    ));
    let 局所光源列 = 定数の検証結果から値を取り出す(局所光源列::生成する(&[点光源]));
    let 影注視点 = 大域位置を作る(影注視点メートル, 影注視点メートル, 影注視点メートル).平行移動する(大域ずらし量);
    ライティング入力::生成する(
        方向光,
        局所光源列,
        定数の検証結果から値を取り出す(環境光係数::生成する(0.03)),
        定数の検証結果から値を取り出す(影入力::生成する(影注視点, メートル::生成する(影光源距離), 既定の影正射影範囲())),
        影の落ち方::落とす,
        有効,
    )
}

/// 世界の宣言が与える設計値であり、強度からの導出ではない(参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断a」)。
pub fn 既定の影響半径を作る() -> 影響半径 {
    クラスタ多光源の検証結果から値を取り出す(影響半径::生成する(メートル::生成する(既定の影響半径メートル)))
}

fn 既定の影正射影範囲() -> 影正射影範囲 {
    定数の検証結果から値を取り出す(影正射影範囲::生成する(
        メートル::生成する(4.0),
        メートル::生成する(4.0),
        メートル::生成する(0.1),
        メートル::生成する(20.0),
    ))
}

fn 大域位置を作る(x: f64, y: f64, z: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(x), 大域メートル::生成する(y), 大域メートル::生成する(z))
}

fn 定数の検証結果から値を取り出す<T>(結果: Result<T, ライティング入力エラー>) -> T {
    結果.unwrap_or_else(|誤り| panic!("既定ライティング定数が不正だった: {誤り}"))
}

fn クラスタ多光源の検証結果から値を取り出す<T>(結果: Result<T, クラスタ多光源入力エラー>) -> T {
    結果.unwrap_or_else(|誤り| panic!("既定ライティングの影響半径が不正だった: {誤り}"))
}
