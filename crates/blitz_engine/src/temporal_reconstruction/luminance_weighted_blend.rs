//! 明るい側の寄与を下げてから履歴と今のフレームを混ぜる工程。受け取るのは履歴の色・今のフレームの色・
//! 今のフレームの寄与率、返すのは混ぜた色である。
//!
//! 固定の割合で混ぜると、表示可能範囲を大きく超える1点が近傍の平均を独り占めし、その1点が動いたあとも
//! 残像として長く残る。明るさの逆数を重みへ掛けると、明るい標本ほど寄与が下がり、残像と明滅が収まる。
//! 光のにじみの抽出が使うKaris平均と同じ族の手法である。
//!
//! 明るさを潰す代わりに全体は暗くならない。重みの和で割り戻すため、両者が同じ明るさなら結果は
//! 指数移動平均と一致する。

use super::current_frame_ratio::今のフレームの寄与率;
use super::error::時間再構成エラー;
use super::linear_color::線形色;
use super::relative_luminance::相対輝度を求める;

/// 注意: 重みを作る2つの割り算・重みの和・成分ごとの積和という演算の順そのものが、slangの写し
/// (`shaders/temporal_reconstruction_blend.slang`)との一致契約である。積和融合を使うと結果が写しと最下位の桁で
/// 食い違い、合成した入力の注入による突き合わせの許容を誤差が食い潰す。
pub fn 輝度で重み付けて混ぜる(
    履歴: 線形色,
    今のフレーム: 線形色,
    寄与率: 今のフレームの寄与率,
) -> Result<線形色, 時間再構成エラー> {
    let 履歴の重み = 寄与率.履歴の寄与率() / (1.0 + 相対輝度を求める(履歴).値());
    let 今の重み = 寄与率.値() / (1.0 + 相対輝度を求める(今のフレーム).値());
    let 重みの和 = 履歴の重み + 今の重み;
    if !重みの和.is_finite() || 重みの和 <= 0.0 {
        return Err(時間再構成エラー::値域外("輝度で重み付けた混合の重みの和", 重みの和));
    }
    let 履歴の成分 = 履歴.成分();
    let 今の成分 = 今のフレーム.成分();
    線形色::生成する(
        一成分を混ぜる(履歴の成分[0], 今の成分[0], 履歴の重み, 今の重み, 重みの和),
        一成分を混ぜる(履歴の成分[1], 今の成分[1], 履歴の重み, 今の重み, 重みの和),
        一成分を混ぜる(履歴の成分[2], 今の成分[2], 履歴の重み, 今の重み, 重みの和),
    )
}

fn 一成分を混ぜる(履歴: f32, 今のフレーム: f32, 履歴の重み: f32, 今の重み: f32, 重みの和: f32) -> f32 {
    (履歴 * 履歴の重み + 今のフレーム * 今の重み) / 重みの和
}
