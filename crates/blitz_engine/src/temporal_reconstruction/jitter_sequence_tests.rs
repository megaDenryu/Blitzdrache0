//! 画素内ずらしの列が決定的であり、画素の内側に収まり、しかも定数でないことを確かめる。
//!
//! 決定性と値域だけを見ると、常に同じ値を返す実装でも通ってしまう。列の全要素が互いに異なることと、
//! 列の重心が画素の中心の近くにあることを対に置く。前者は定数実装を、後者は片側へ偏った実装を落とす。

#![allow(clippy::unwrap_used)]

use super::{ずらしの列の添字, 画素を単位とするずらしを求める};

const 許容: f32 = 1.0e-6;
/// 列の重心が画素の中心からどれだけ離れてよいか。8点の低食い違い列の重心はこの範囲へ入る。
const 重心の許容: f32 = 0.1;

fn 列を求める() -> Vec<(f32, f32)> {
    (0..ずらしの列の添字::列の長さ())
        .map(|番号| {
            let ずらし = 画素を単位とするずらしを求める(ずらしの列の添字::生成する(番号).unwrap()).unwrap();
            (ずらし.横(), ずらし.縦())
        })
        .collect()
}

#[test]
fn 同じ添字からは同じ値が出る() {
    assert_eq!(列を求める(), 列を求める());
}

#[test]
fn フレーム番号は列の長さで折り返す() {
    let 長さ = ずらしの列の添字::列の長さ();
    for 番号 in 0..長さ {
        assert_eq!(
            ずらしの列の添字::フレーム番号から求める(番号),
            ずらしの列の添字::フレーム番号から求める(番号 + 長さ)
        );
    }
    assert_eq!(ずらしの列の添字::フレーム番号から求める(長さ).値(), 0);
}

#[test]
fn 列の全要素が半画素の内側にある() {
    for (横, 縦) in 列を求める() {
        assert!(横.abs() < 0.5, "横が半画素を超えた: {横}");
        assert!(縦.abs() < 0.5, "縦が半画素を超えた: {縦}");
    }
}

/// 定数を返す実装はこの検査で落ちる。
#[test]
fn 列の要素は互いに異なる() {
    let 列 = 列を求める();
    for 手前 in 0..列.len() {
        for 後ろ in (手前 + 1)..列.len() {
            let 隔たり = (列[手前].0 - 列[後ろ].0).abs() + (列[手前].1 - 列[後ろ].1).abs();
            assert!(隔たり > 許容, "{手前}番目と{後ろ}番目のずらしが同じである");
        }
    }
}

/// 片側へ偏った列はこの検査で落ちる。
#[test]
fn 列の重心は画素の中心の近くにある() {
    let 列 = 列を求める();
    let 件数 = f32::from(u16::try_from(列.len()).unwrap());
    let 横の重心 = 列.iter().map(|要素| 要素.0).sum::<f32>() / 件数;
    let 縦の重心 = 列.iter().map(|要素| 要素.1).sum::<f32>() / 件数;
    assert!(横の重心.abs() < 重心の許容, "横の重心が偏った: {横の重心}");
    assert!(縦の重心.abs() < 重心の許容, "縦の重心が偏った: {縦の重心}");
}

/// 列の先頭は基数2と基数3の1番目の桁反転から出る。桁の並べ替えを取り違えた実装はここで落ちる。
#[test]
fn 列の先頭は基数ごとの一番目の値である() {
    let 先頭 = 画素を単位とするずらしを求める(ずらしの列の添字::生成する(0).unwrap()).unwrap();
    assert!((先頭.横() - 0.0).abs() < 許容, "横が基数2の1番目と違う: {}", 先頭.横());
    assert!((先頭.縦() - (1.0 / 3.0 - 0.5)).abs() < 許容, "縦が基数3の1番目と違う: {}", 先頭.縦());
}

#[test]
fn 列の長さを超えた添字を拒む() {
    assert!(ずらしの列の添字::生成する(ずらしの列の添字::列の長さ()).is_err());
    assert!(ずらしの列の添字::生成する(ずらしの列の添字::列の長さ() - 1).is_ok());
}

#[test]
fn 画素の単位から正規化装置座標へ写せる() {
    let ずらし = 画素を単位とするずらしを求める(ずらしの列の添字::生成する(2).unwrap()).unwrap();
    let 写した = ずらし.正規化装置座標へ写す(1920, 1080).unwrap();
    assert!((写した.正規化装置座標の横() - ずらし.横() * 2.0 / 1920.0).abs() < 許容);
    assert!((写した.正規化装置座標の縦() - ずらし.縦() * 2.0 / 1080.0).abs() < 許容);
}
