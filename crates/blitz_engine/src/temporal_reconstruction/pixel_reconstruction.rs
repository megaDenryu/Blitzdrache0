//! 1画素ぶんの再構成の合成そのもの。受け取るのは今のフレームの色・履歴の色・近傍の色の範囲・履歴の採否・
//! 今のフレームの寄与率、返すのは再構成後の色である。
//!
//! 部品ごとの純関数と別にこの1本を置くのは、合成の順そのものがこの方式の正本だからである。順を型に置かないと、
//! 段3bでslangの写しとxtaskの検収ハーネスが同じ順を別々に書き、片方だけを直した食い違いが絵にしか出なくなる。
//!
//! 順は3段であり、それぞれ入れ替えられない理由を持つ。
//!
//! 第一に採否を最初に見る。捨てる画素では履歴の色も近傍の色の範囲も結果へ1つも関与してはならない。
//! 混ぜてから捨てる形にすると、捨てた画素の結果が混合の丸め誤差の分だけ今のフレームの色から離れ、
//! 履歴を無効化した直後の1フレーム目が今のフレームと一致するという判断cの規律が画素で破れる。
//!
//! 第二に、収めてから混ぜる。収めは「今のフレームではありえない履歴」を近傍が張る範囲へ引き戻す操作であり、
//! 混合の入力を正すためにある。混ぜてから収めると2つが壊れる。1つは混合の重みであり、輝度による重み付けが
//! 収める前の極端に明るい履歴で決まってしまい、本来抑えるべき残像をそのまま通す。もう1つは今のフレームの色の
//! 扱いであり、履歴の誤差が乗った結果を範囲へ当てることになるため、範囲の端に張り付いた画素では今のフレームの
//! 色まで一緒に歪む。
//!
//! 第三に、混ぜるのは指数移動平均でなく輝度で重み付けた混合である。収めたあとでも近傍の範囲そのものが広ければ
//! 明るい標本は残るため、明滅を抑える重みが要る。2つの輝度が等しいとき、この混合は指数移動平均と一致する。

use super::current_frame_ratio::今のフレームの寄与率;
use super::error::時間再構成エラー;
use super::history_admission::履歴の採否;
use super::linear_color::線形色;
use super::luminance_weighted_blend::輝度で重み付けて混ぜる;
use super::neighborhood_range::近傍の色の範囲;

pub fn 一画素を再構成する(
    今のフレームの色: 線形色,
    履歴の色: 線形色,
    近傍の範囲: 近傍の色の範囲,
    採否: 履歴の採否,
    寄与率: 今のフレームの寄与率,
) -> Result<線形色, 時間再構成エラー> {
    match 採否 {
        履歴の採否::画面の外だから捨てる | 履歴の採否::出現領域だから捨てる => Ok(今のフレームの色),
        履歴の採否::採る => {
            let 収めた履歴 = 近傍の範囲.収める(履歴の色)?;
            輝度で重み付けて混ぜる(収めた履歴, 今のフレームの色, 寄与率)
        }
    }
}
