//! 線形の色がどれだけ明るく見えるかを表す1つの量と、色からその量を求める工程。
//!
//! 混合の重みを色の成分そのものでなく輝度で決めるのは、明るい1点が残す残像と明滅が、成分のどれか1つでなく
//! 見かけの明るさに比例して目立つためである。緑に大きな重みが載るBT.709の係数を使うのはそのためである。

use super::constants::{緑の重み, 赤の重み, 青の重み};
use super::error::時間再構成エラー;
use super::linear_color::線形色;

/// 線形の色の見かけの明るさ。
/// 不変条件: 有限かつ0以上である。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 相対輝度 {
    値: f32,
}

impl 相対輝度 {
    pub fn 生成する(値: f32) -> Result<Self, 時間再構成エラー> {
        if !値.is_finite() || 値 < 0.0 {
            return Err(時間再構成エラー::値域外("相対輝度", 値));
        }
        Ok(Self { 値 })
    }

    pub fn 値(self) -> f32 {
        self.値
    }
}

/// 線形の色から相対輝度を求める。
///
/// 注意: 3つの積を先に丸め、赤と緑の和を採ってから青を足す、この演算の順そのものが段3bで入るslangの写しとの
/// 一致契約である。積和融合(乗算と加算を1命令にまとめ、積の丸めを省く最適化)を使うと、混合の重みが写しと
/// 最下位の桁で食い違い、合成した入力の注入による突き合わせが通らなくなる。
///
/// 前提: 線形色の3成分が有限かつ0以上であり、3つの重みがいずれも正であるから、結果は必ず有限かつ0以上になる。
pub fn 相対輝度を求める(色: 線形色) -> 相対輝度 {
    let [赤, 緑, 青] = 色.成分();
    相対輝度 {
        値: 赤 * 赤の重み + 緑 * 緑の重み + 青 * 青の重み,
    }
}
