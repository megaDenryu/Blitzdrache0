//! 輝度で重み付けた混合が、明るい側の寄与を下げることを確かめる。担うのは、明るい履歴が結果を引っ張らないこと、
//! 両者の輝度が等しいときは指数移動平均と一致すること、両端の寄与率で片方がそのまま残ることである。
//!
//! 明るい側が下がることだけを見ると、常に今のフレームを返す実装でも通ってしまう。輝度が等しいときに
//! 指数移動平均と一致することと、両端の寄与率が効くことを対に置く。前者は重み付けを常に効かせる実装を、
//! 後者は寄与率を無視する実装を落とす。

#![allow(clippy::unwrap_used)]

use super::{
    今のフレームの寄与率, 指数移動平均で混ぜる, 相対輝度, 相対輝度を求める, 線形色, 輝度で重み付けて混ぜる
};

const 許容: f32 = 1.0e-5;

fn 寄与率(値: f32) -> 今のフレームの寄与率 {
    今のフレームの寄与率::生成する(値).unwrap()
}

/// 輝度を無視して指数移動平均へ委譲した実装はこの検査で落ちる。
#[test]
fn 明るい履歴は結果を引っ張らない() {
    let 履歴 = 線形色::生成する(10.0, 10.0, 10.0).unwrap();
    let 今 = 線形色::生成する(0.1, 0.1, 0.1).unwrap();
    let 重み付き = 輝度で重み付けて混ぜる(履歴, 今, 寄与率(0.5)).unwrap().成分()[0];
    let 平均 = 指数移動平均で混ぜる(履歴, 今, 寄与率(0.5)).unwrap().成分()[0];
    assert!(重み付き < 平均, "明るい履歴の寄与が下がっていない(重み付き{重み付き}・平均{平均})");
    assert!((重み付き - 今.成分()[0]).abs() < (平均 - 今.成分()[0]).abs());
}

/// 明るい側が今のフレームなら、下がるのは今のフレームの寄与である。片側だけを見た実装はここで落ちる。
#[test]
fn 明るい今のフレームも結果を引っ張らない() {
    let 履歴 = 線形色::生成する(0.1, 0.1, 0.1).unwrap();
    let 今 = 線形色::生成する(10.0, 10.0, 10.0).unwrap();
    let 重み付き = 輝度で重み付けて混ぜる(履歴, 今, 寄与率(0.5)).unwrap().成分()[0];
    let 平均 = 指数移動平均で混ぜる(履歴, 今, 寄与率(0.5)).unwrap().成分()[0];
    assert!(
        重み付き < 平均,
        "明るい今のフレームの寄与が下がっていない(重み付き{重み付き}・平均{平均})"
    );
}

/// 重み付けを常に効かせる実装はこの検査で落ちる。輝度が等しければ重みは寄与率だけで決まる。
#[test]
fn 輝度が等しければ指数移動平均と一致する() {
    let 履歴 = 線形色::生成する(1.0, 0.0, 0.0).unwrap();
    let 今 = 線形色::生成する(0.0, 相対輝度を求める(履歴).値() / 0.7152, 0.0).unwrap();
    let 重み付き = 輝度で重み付けて混ぜる(履歴, 今, 寄与率(0.25)).unwrap().成分();
    let 平均 = 指数移動平均で混ぜる(履歴, 今, 寄与率(0.25)).unwrap().成分();
    for 位置 in 0..3 {
        assert!(
            (重み付き[位置] - 平均[位置]).abs() < 許容,
            "{位置}番目の成分が指数移動平均と食い違う(重み付き{}・平均{})",
            重み付き[位置],
            平均[位置]
        );
    }
}

#[test]
fn 両端の寄与率では片方がそのまま残る() {
    let 履歴 = 線形色::生成する(4.0, 2.0, 1.0).unwrap();
    let 今 = 線形色::生成する(0.5, 0.25, 0.125).unwrap();
    let 履歴のまま = 輝度で重み付けて混ぜる(履歴, 今, 寄与率(0.0)).unwrap().成分();
    let 今のまま = 輝度で重み付けて混ぜる(履歴, 今, 寄与率(1.0)).unwrap().成分();
    for 位置 in 0..3 {
        assert!((履歴のまま[位置] - 履歴.成分()[位置]).abs() < 許容, "寄与率零で履歴が残らない");
        assert!((今のまま[位置] - 今.成分()[位置]).abs() < 許容, "寄与率一で今のフレームが残らない");
    }
}

#[test]
fn 相対輝度は緑に最も大きな重みを載せる() {
    let 赤 = 相対輝度を求める(線形色::生成する(1.0, 0.0, 0.0).unwrap()).値();
    let 緑 = 相対輝度を求める(線形色::生成する(0.0, 1.0, 0.0).unwrap()).値();
    let 青 = 相対輝度を求める(線形色::生成する(0.0, 0.0, 1.0).unwrap()).値();
    assert!(青 < 赤 && 赤 < 緑, "重みの大小が違う(赤{赤}・緑{緑}・青{青})");
    assert!((赤 + 緑 + 青 - 1.0).abs() < 許容, "3つの重みの和が1でない");
}

#[test]
fn 相対輝度は非有限と負を拒む() {
    assert!(相対輝度::生成する(-0.1).is_err());
    assert!(相対輝度::生成する(f32::NAN).is_err());
    assert!(相対輝度::生成する(0.0).is_ok());
}
