//! その画素で履歴を採るか捨てるかの判定そのもの。受け取るのは前のフレームの位置と2つの奥行きと許容、
//! 返すのは採否とその理由である。
//!
//! 採否を真偽値でなく理由付きの判別共用体で返すのは、捨てた理由が絵の上で同じに見えるためである。
//! 履歴が混ざらない画素を見て、それが画面の外へ出たからなのか手前の物の陰から現れたからなのかは、
//! 判定の側が言わないかぎり分からない。検収はこの理由の分布を見て、棄却が想定どおりの原因で
//! 起きているかを確かめる。

use super::disocclusion_tolerance::出現領域の相対許容;
use super::screen_position::画面上の位置;
use super::view_depth::ビュー空間の奥行き;

/// その画素で履歴を採るか、捨てるならなぜ捨てるか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 履歴の採否 {
    採る,
    /// 前のフレームの位置が画面の外にあり、参照できる履歴がそもそも存在しない。
    画面の外だから捨てる,
    /// 奥行きが食い違い、前のフレームでは手前の物に隠れていたと判定した(出現領域)。
    出現領域だから捨てる,
}

/// 履歴を採るかを判定する。画面の外かを先に見るのは、外の位置で参照した奥行きに意味が無く、
/// 奥行きの照合を先に置くと意味の無い値の比較結果が理由を決めてしまうためである。
pub fn 履歴を採るか判定する(
    前のフレームの位置: 画面上の位置,
    前のフレームの奥行き: ビュー空間の奥行き,
    今のフレームの奥行き: ビュー空間の奥行き,
    許容: 出現領域の相対許容,
) -> 履歴の採否 {
    if !前のフレームの位置.画面の内側か() {
        return 履歴の採否::画面の外だから捨てる;
    }
    if 許容.同じ面とみなすか(前のフレームの奥行き, 今のフレームの奥行き) {
        履歴の採否::採る
    } else {
        履歴の採否::出現領域だから捨てる
    }
}
