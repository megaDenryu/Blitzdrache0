//! 今のフレームの色が結果へ占める割合そのもの。担うのは値域の保証と、履歴の側の割合を導くことである。
//!
//! 履歴の側の割合を別の値として持たないのは、2つを別々に受け取ると和が1にならない組を呼び出し側が
//! 作れてしまい、混合が色を増やしたり減らしたりするためである。片方だけを持ち、もう片方は導く。

use super::constants::既定の今のフレームの寄与率;
use super::error::時間再構成エラー;

/// 今のフレームの色が結果へ占める割合。0なら履歴がそのまま残り、1なら履歴を使わない。
/// 不変条件: 有限かつ0以上1以下である。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 今のフレームの寄与率 {
    値: f32,
}

impl 今のフレームの寄与率 {
    pub fn 生成する(値: f32) -> Result<Self, 時間再構成エラー> {
        if !値.is_finite() || !(0.0..=1.0).contains(&値) {
            return Err(時間再構成エラー::値域外("今のフレームの寄与率", 値));
        }
        Ok(Self { 値 })
    }

    /// 列の長さと釣り合わせた既定の割合。根拠は定数の宣言に書いてある。
    pub fn 既定() -> Self {
        Self {
            値: 既定の今のフレームの寄与率,
        }
    }

    pub fn 値(self) -> f32 {
        self.値
    }

    /// 履歴の色が結果へ占める割合。2つの割合の和は常に1である。
    pub fn 履歴の寄与率(self) -> f32 {
        1.0 - self.値
    }
}
