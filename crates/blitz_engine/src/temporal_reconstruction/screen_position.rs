//! 画面上の1点を正規化装置座標で表す位置そのもの。担うのは2成分の有限性の保証と、その点が画面の内側かの判別である。
//!
//! 値域を画面の内側へ縛らないのは、この型が主に前のフレームの位置を運ぶためである。カメラが動けば今のフレームの
//! 画素の前のフレームの位置は画面の外へ出うるのであって、それは壊れた値ではなく履歴を捨てる根拠になる正しい値である。
//! 生成の時点で外を拒むと、この根拠を型付きエラーとして扱うことになり、失敗と正常な判定が見分けられなくなる。

use super::error::時間再構成エラー;

/// 正規化装置座標での画面上の位置。横は右が正、縦は下が正であり、画面の内側は2成分とも-1以上1以下である。
/// 不変条件: 2成分とも有限である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 画面上の位置 {
    横: f32,
    縦: f32,
}

impl 画面上の位置 {
    pub fn 生成する(横: f32, 縦: f32) -> Result<Self, 時間再構成エラー> {
        if !横.is_finite() {
            return Err(時間再構成エラー::値域外("画面上の位置の横", 横));
        }
        if !縦.is_finite() {
            return Err(時間再構成エラー::値域外("画面上の位置の縦", 縦));
        }
        Ok(Self { 横, 縦 })
    }

    pub fn 横(self) -> f32 {
        self.横
    }

    pub fn 縦(self) -> f32 {
        self.縦
    }

    /// その点が画面の内側にあるか。外にある点には参照できる履歴が無く、履歴を捨てる根拠になる。
    pub fn 画面の内側か(self) -> bool {
        (-1.0..=1.0).contains(&self.横) && (-1.0..=1.0).contains(&self.縦)
    }
}
