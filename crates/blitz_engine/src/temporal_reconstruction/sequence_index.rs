//! 画素内ずらしの列の何番目を使うかを表す添字そのもの。担うのは列の長さの内側であることの保証と、
//! フレーム番号からの折り返しである。
//!
//! フレーム番号をそのまま列へ渡さないのは、折り返しの余りを取る場所が2つ以上に増えると、列の長さを変えたときに
//! 片方だけが取り残されるためである。折り返しはこの型の生成の1箇所に閉じる。

use super::constants::列の長さ;
use super::error::時間再構成エラー;

/// 画素内ずらしの列の中の位置。
/// 不変条件: 列の長さより小さい。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ずらしの列の添字 {
    値: u32,
}

impl ずらしの列の添字 {
    pub fn 生成する(値: u32) -> Result<Self, 時間再構成エラー> {
        if 値 >= 列の長さ {
            return Err(時間再構成エラー::整数値域外("ずらしの列の添字", 値));
        }
        Ok(Self { 値 })
    }

    /// フレーム番号を列の長さで折り返した添字。同じフレーム番号からは常に同じ添字が出る。
    pub fn フレーム番号から求める(フレーム番号: u32) -> Self {
        Self {
            値: フレーム番号 % 列の長さ
        }
    }

    pub fn 値(self) -> u32 {
        self.値
    }

    /// 列が一周する長さ。検収が周期の全体を観測するために外から読む。
    pub fn 列の長さ() -> u32 {
        列の長さ
    }
}
