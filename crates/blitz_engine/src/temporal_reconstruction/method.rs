//! 世界が宣言する時間再構成方式のCPU正本。担うのは、過去のフレームの結果を今のフレームへ混ぜるかどうかという
//! 1つの選択を、間接照明方針・露出方式・拡散間接方式に続く第4の軸として型で表すことである。
//!
//! 既存の3軸と同じ形にするのは、世界ごとの宣言・起動指定による上書き・GPU境界への写しという3つの経路が
//! 軸ごとに違う形になると、どの軸がどこで決まるかを読み手が軸ごとに追い直さなければならなくなるためである。
//!
//! この軸が決めるのは時間再構成のパスを積むかどうかだけである。動きベクトル画像と履歴画像の資源は方式に依らず
//! 常に作る。資源の有無を方式へ連動させると、積まない方式のときに「知らないキー」と「作っていないキー」が
//! 同じ失敗に見えるためである。
//! 参照: `_doc/設計/時間再構成.md`「判断e: 世界宣言の第4軸と検収の保護」

/// 世界が宣言する時間再構成の方式。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 時間再構成方式 {
    /// 今のフレームの結果をそのまま出す。過去のフレームの色を1画素も読まない。
    使わない,
    /// 動きベクトルで写した前のフレームの色を今のフレームの色へ混ぜる。
    履歴混合,
}
