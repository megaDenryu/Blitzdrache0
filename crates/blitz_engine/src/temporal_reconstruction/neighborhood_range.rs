//! 今のフレームの近傍の色が張る範囲そのもの。担うのは近傍からの範囲の組み立てと、その範囲へ履歴を収めることである。
//!
//! 履歴をこの範囲へ収めるのは、動く縁や照明の変化で履歴が今のフレームのどの近傍にも似ていない色になることが
//! あり、それをそのまま混ぜると尾を引いた残像が残るためである。範囲を今のフレームの近傍から作れば、
//! 履歴の色は「今のフレームでもありえた色」の内側へ必ず入る。
//!
//! 範囲を成分ごとの最小と最大で持つのは、この範囲の役目が「ありえない色を止めること」だからである。
//! 範囲を狭く採るほど残像は消えるが、ずらしで稼いだ標本の差そのものも消える。

use super::error::時間再構成エラー;
use super::linear_color::線形色;

/// 近傍の色が成分ごとに取る最小と最大。
/// 不変条件: 成分ごとに最小が最大以下である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 近傍の色の範囲 {
    最小: 線形色,
    最大: 線形色,
}

impl 近傍の色の範囲 {
    /// 今のフレームの近傍の色から範囲を作る。近傍には自分自身の画素を含めるのが通例である。
    pub fn 近傍から求める(近傍: &[線形色]) -> Result<Self, 時間再構成エラー> {
        let Some((先頭, 残り)) = 近傍.split_first() else {
            return Err(時間再構成エラー::要素が空("近傍の色"));
        };
        let mut 最小 = 先頭.成分();
        let mut 最大 = 先頭.成分();
        for 色 in 残り {
            let 成分 = 色.成分();
            for 位置 in 0..3 {
                最小[位置] = 最小[位置].min(成分[位置]);
                最大[位置] = 最大[位置].max(成分[位置]);
            }
        }
        Ok(Self {
            最小: 線形色::成分から生成する(最小)?,
            最大: 線形色::成分から生成する(最大)?,
        })
    }

    pub fn 最小(self) -> 線形色 {
        self.最小
    }

    pub fn 最大(self) -> 線形色 {
        self.最大
    }

    /// 色を範囲の内側へ成分ごとに収める。すでに内側にある色はそのまま返る。
    pub fn 収める(self, 色: 線形色) -> Result<線形色, 時間再構成エラー> {
        let 元 = 色.成分();
        let 下限 = self.最小.成分();
        let 上限 = self.最大.成分();
        線形色::生成する(
            元[0].clamp(下限[0], 上限[0]),
            元[1].clamp(下限[1], 上限[1]),
            元[2].clamp(下限[2], 上限[2]),
        )
    }
}
