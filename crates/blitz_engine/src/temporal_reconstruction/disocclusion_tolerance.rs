//! 2つの奥行きが同じ面のものだと認める食い違いの上限を、今のフレームの奥行きに対する割合で表した量そのもの。
//! 担うのは値域の保証と、2つの奥行きの照合である。
//!
//! 絶対の長さでなく割合で持つのは、この照合の誤差が奥行きに比例するためである。誤差の出どころは2つあり、
//! どちらも比例する。1つは履歴画像の第4成分の半精度が持つ相対誤差であり、浮動小数の相対誤差は値の大きさに
//! よらず一定である。もう1つは1フレームぶんのカメラの移動を写し戻すときの誤差であり、遠いほど大きく出る。
//! 絶対の長さで持つと、近くでは緩すぎて遠くでは厳しすぎる1つの値しか選べない。

use super::constants::既定の出現領域の相対許容;
use super::error::時間再構成エラー;
use super::view_depth::ビュー空間の奥行き;

/// 同じ面のものだと認める奥行きの食い違いの上限を、今のフレームの奥行きへの割合で表した値。
/// 不変条件: 有限であり、0より大きく1より小さい。1以上では奥行きが倍に跳んでも同じ面と認めてしまう。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 出現領域の相対許容 {
    値: f32,
}

impl 出現領域の相対許容 {
    pub fn 生成する(値: f32) -> Result<Self, 時間再構成エラー> {
        if !値.is_finite() || 値 <= 0.0 || 値 >= 1.0 {
            return Err(時間再構成エラー::値域外("出現領域の相対許容", 値));
        }
        Ok(Self { 値 })
    }

    /// 誤差の大きさと奥行きの跳びの大きさの隔たりから採った既定の割合。根拠は定数の宣言に書いてある。
    pub fn 既定() -> Self {
        Self {
            値: 既定の出現領域の相対許容,
        }
    }

    pub fn 値(self) -> f32 {
        self.値
    }

    /// 2つの奥行きが同じ面のものだと認められるか。割合を掛ける相手を今のフレームの側に採るのは、
    /// 前のフレームの奥行きが写し戻しの誤差を既に含んでおり、基準に据えると許容そのものが揺れるためである。
    pub fn 同じ面とみなすか(
        self, 前のフレームの奥行き: ビュー空間の奥行き, 今のフレームの奥行き: ビュー空間の奥行き
    ) -> bool {
        let 食い違い = (前のフレームの奥行き.値().値() - 今のフレームの奥行き.値().値()).abs();
        食い違い <= self.値 * 今のフレームの奥行き.値().値()
    }
}
