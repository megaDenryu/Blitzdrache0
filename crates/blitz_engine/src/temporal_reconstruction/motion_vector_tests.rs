//! 動きベクトルの規約が型の上で守られていることを確かめる。担うのは、向きが今のフレームから前のフレームへ
//! 向いていること、動いていない値が位置を動かさないこと、非有限を拒むことである。
//!
//! 向きの検査は往復だけでは足りない。符号を反転した実装でも、作るときと戻すときで同じ符号を使えば往復は
//! 閉じてしまう。作った成分そのものの符号を見る検査を対に置く。

#![allow(clippy::unwrap_used)]

use super::{動きベクトル, 画面上の位置};

const 許容: f32 = 1.0e-6;

#[test]
fn 二つの位置から作った値を今の位置へ足すと前の位置へ戻る() {
    let 今 = 画面上の位置::生成する(-0.25, 0.5).unwrap();
    let 前 = 画面上の位置::生成する(0.5, -0.125).unwrap();
    let ベクトル = 動きベクトル::二つの位置から求める(今, 前).unwrap();
    let 戻した = ベクトル.前のフレームの位置(今).unwrap();
    assert!((戻した.横() - 前.横()).abs() < 許容, "横が戻らない: {}", 戻した.横());
    assert!((戻した.縦() - 前.縦()).abs() < 許容, "縦が戻らない: {}", 戻した.縦());
}

/// 向きは今のフレームから前のフレームへ向かう。符号を反転した実装はこの検査で落ちる。
#[test]
fn 成分の符号は前のフレームへ向かう向きである() {
    let 今 = 画面上の位置::生成する(0.0, 0.0).unwrap();
    let 前 = 画面上の位置::生成する(0.5, 0.25).unwrap();
    let ベクトル = 動きベクトル::二つの位置から求める(今, 前).unwrap();
    assert!(
        (ベクトル.正規化装置座標の横() - 0.5).abs() < 許容,
        "横の符号が逆である: {}",
        ベクトル.正規化装置座標の横()
    );
    assert!(
        (ベクトル.正規化装置座標の縦() - 0.25).abs() < 許容,
        "縦の符号が逆である: {}",
        ベクトル.正規化装置座標の縦()
    );
}

#[test]
fn 動いていない値は位置を動かさない() {
    let 今 = 画面上の位置::生成する(0.75, -0.5).unwrap();
    let 戻した = 動きベクトル::動いていない().前のフレームの位置(今).unwrap();
    assert_eq!(戻した, 今);
}

#[test]
fn 非有限の成分を拒む() {
    assert!(動きベクトル::生成する(f32::NAN, 0.0).is_err());
    assert!(動きベクトル::生成する(0.0, f32::INFINITY).is_err());
    assert!(動きベクトル::生成する(3.0, -3.0).is_ok());
}

/// 前のフレームの位置は画面の外へ出うる。生成が外を拒まないことを確かめる対の検査であり、
/// これが拒まれると棄却の判定が型付きエラーへすり替わる。
#[test]
fn 前のフレームの位置は画面の外へ出られる() {
    let 今 = 画面上の位置::生成する(0.9, 0.0).unwrap();
    let ベクトル = 動きベクトル::生成する(0.5, 0.0).unwrap();
    let 前 = ベクトル.前のフレームの位置(今).unwrap();
    assert!(!前.画面の内側か(), "画面の外の位置が内側と判定された: {}", 前.横());
    assert!(画面上の位置::生成する(0.5, 0.5).unwrap().画面の内側か());
}
