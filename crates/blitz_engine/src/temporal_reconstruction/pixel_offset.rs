//! 標本の位置を画素の中心からどれだけ動かすかを、画素を単位として表した量そのもの。担うのは1画素の内側に
//! 収まっていることの保証と、画面の画素数を与えて正規化装置座標へ写すことである。
//!
//! 列が作る値をいったん画素の単位で持つのは、列そのものが画面の画素数を知らずに定まるためである。
//! 画素数に依存する換算はこの型の写しの1箇所だけで起こり、列の側は解像度が変わっても同じ値を返す。

use blitz_math::{画素内ずらし, 画素内ずらしエラー};

use super::error::時間再構成エラー;

/// 画素の中心からのずらし。横は右が正、縦は下が正である。
/// 不変条件: 2成分とも有限であり、大きさは半画素より小さい。半画素はその画素の受け持つ範囲の端であり、
/// これを超えた標本は隣の画素の範囲へ入る。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 画素を単位とするずらし {
    横: f32,
    縦: f32,
}

impl 画素を単位とするずらし {
    pub fn 生成する(横: f32, 縦: f32) -> Result<Self, 時間再構成エラー> {
        if !横.is_finite() || 横.abs() >= 0.5 {
            return Err(時間再構成エラー::値域外("画素を単位とするずらしの横", 横));
        }
        if !縦.is_finite() || 縦.abs() >= 0.5 {
            return Err(時間再構成エラー::値域外("画素を単位とするずらしの縦", 縦));
        }
        Ok(Self { 横, 縦 })
    }

    pub fn 横(self) -> f32 {
        self.横
    }

    pub fn 縦(self) -> f32 {
        self.縦
    }

    /// 画面の画素数を与えて、射影へ足せる形へ写す。
    pub fn 正規化装置座標へ写す(
        self, 横の画素数: u32, 縦の画素数: u32
    ) -> Result<画素内ずらし, 画素内ずらしエラー> {
        画素内ずらし::画素から生成する(self.横, self.縦, 横の画素数, 縦の画素数)
    }
}
