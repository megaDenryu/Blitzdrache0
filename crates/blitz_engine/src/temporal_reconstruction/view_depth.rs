//! カメラから面までの、視線方向に測った隔たりそのもの。担うのは正であることと有限であることの保証だけである。
//!
//! 深度バッファの0から1の値でなくメートルで持つのは、棄却の判定が2つの奥行きの差を比べるためである。
//! 深度バッファの値は近クリップ面の近くへ強く偏るため、同じ差の値が距離によって別の意味を持つ。
//! 履歴画像の第4成分がこの線形の奥行きを持ち回るのはこの理由による。
//! 参照: `_doc/設計/時間再構成.md`「判断f: 純関数層の中身」

use blitz_math::メートル;

use super::error::時間再構成エラー;

/// カメラの視線方向に測った面までの隔たり。
/// 不変条件: 有限かつ正である。カメラの後ろや近クリップ面の上の点は画面に現れない。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct ビュー空間の奥行き {
    値: メートル,
}

impl ビュー空間の奥行き {
    pub fn 生成する(値: メートル) -> Result<Self, 時間再構成エラー> {
        if !値.値().is_finite() || 値.値() <= 0.0 {
            return Err(時間再構成エラー::値域外("ビュー空間の奥行き", 値.値()));
        }
        Ok(Self { 値 })
    }

    pub fn 値(self) -> メートル {
        self.値
    }
}
