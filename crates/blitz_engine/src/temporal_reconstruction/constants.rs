//! 段3bでslangの写しが同じ値を持たなければならない定数を、この層の1箇所に集めたもの。
//! 触れる状態を持たず、担うのは値そのものと、その値をなぜその大きさに採ったかの根拠である。
//!
//! 値をそれぞれの型の中へ散らさないのは、写しとの突き合わせを`cargo xtask conform`の定数一致検査へ
//! 登録するときに、正本の宣言がどこにあるかを1つのファイルで言い切れるようにするためである。
//! 登録そのものはslangの写しが入る段3bで行う。
//! 参照: `_doc/設計/時間再構成.md`「判断f: 純関数層の中身」

/// 画素内ずらしの列が一周する長さ。
///
/// 8を採るのは2つの理由による。第一に、定常状態はこの長さを周期とする周期軌道であり、静止カメラでの
/// 安定を判定する検収は周期の全体を観測しなければならないため、短いほど検収の実行が軽い。
/// 第二に、既定の今のフレームの寄与率が作る実効の平均窓(寄与率の逆数で10フレーム)がこの長さを上回り、
/// 周期の全ての標本位置が収束値へ寄与する。長さを16へ上げるなら寄与率も同時に下げる必要がある。
pub(super) const 列の長さ: u32 = 8;

/// ハルトン列の横成分の基数。互いに素な最小の2つの素数を横と縦へ割り当てると、2次元の食い違いが最も小さくなる。
/// 型を16ビットに採るのは、標準ライブラリが単精度への型付き変換をこの幅までしか持たず、数値の`as`キャストが規約で禁じられているためである。
pub(super) const 横の基数: u16 = 2;
/// ハルトン列の縦成分の基数。
pub(super) const 縦の基数: u16 = 3;

/// 相対輝度Y = 0.2126R + 0.7152G + 0.0722B(BT.709の係数)の3成分の重み。
///
/// 注意: 自動露出の層(`crates/blitz_engine/src/auto_exposure/luminance.rs`)と同じ定義でなければならない。
/// 同じ線形の色に対して2つの輝度の定義が並ぶと、露出が明るいと判定した画素を混合が暗いと重み付ける食い違いが起こる。
/// この一致は`crates/blitz_engine/src/auto_exposure/temporal_luminance_agreement_tests.rs`が検査している。
pub(super) const 赤の重み: f32 = 0.2126;
pub(super) const 緑の重み: f32 = 0.7152;
pub(super) const 青の重み: f32 = 0.0722;

/// 今のフレームの色が結果へ占める既定の割合。実効の平均窓はこの逆数のフレーム数であり、0.1で10フレームになる。
/// 列の長さ8を上回る窓を採るのは、周期の全ての標本位置が収束値へ寄与しなければ、ずらしで稼いだ標本数が絵に出ないためである。
pub(super) const 既定の今のフレームの寄与率: f32 = 0.1;

/// 前のフレームの奥行きと今のフレームの奥行きが同じ面のものだと認める、今の奥行きに対する食い違いの割合。
///
/// 0.05を採る根拠は誤差と信号の大きさの隔たりである。この比較の誤差は主に、履歴画像の第4成分の半精度が持つ
/// 相対誤差(約0.05パーセント)と、1フレームぶんのカメラの移動を写し戻すときの誤差であり、どちらも今の奥行きに
/// 比例する。一方で本当に手前の物へ隠れていた画素の奥行きは数倍の隔たりで跳ぶ。5パーセントは誤差の側から
/// 2桁の余白を採りつつ、跳びの側からは1桁以上低い。
pub(super) const 既定の出現領域の相対許容: f32 = 0.05;
