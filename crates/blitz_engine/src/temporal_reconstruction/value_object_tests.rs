//! 列と位置の値オブジェクトが壊れた入力を拒むことを確かめる。担うのは、半画素の外のずらし・非有限の位置・
//! 画素数が零の写しが型付きの失敗になることと、画面の内外の境界がどちらに入るかである。
//!
//! 受け付ける側も対で置く。拒む側だけを見ると、常に失敗を返す実装でも通ってしまう。

#![allow(clippy::unwrap_used)]

use super::{時間再構成エラー, 画素を単位とするずらし, 画面上の位置};

#[test]
fn 画素を単位とするずらしは半画素の外を拒む() {
    assert!(画素を単位とするずらし::生成する(0.5, 0.0).is_err());
    assert!(画素を単位とするずらし::生成する(0.0, -0.5).is_err());
    assert!(画素を単位とするずらし::生成する(f32::NAN, 0.0).is_err());
    assert!(画素を単位とするずらし::生成する(0.499, -0.499).is_ok());
}

#[test]
fn 画素数が零なら正規化装置座標へ写せない() {
    let ずらし = 画素を単位とするずらし::生成する(0.25, -0.25).unwrap();
    assert!(ずらし.正規化装置座標へ写す(0, 1080).is_err());
    assert!(ずらし.正規化装置座標へ写す(1920, 0).is_err());
    assert!(ずらし.正規化装置座標へ写す(1920, 1080).is_ok());
}

#[test]
fn 画面上の位置は非有限を拒む() {
    assert!(画面上の位置::生成する(f32::INFINITY, 0.0).is_err());
    assert!(画面上の位置::生成する(0.0, f32::NAN).is_err());
    assert!(画面上の位置::生成する(-3.0, 3.0).is_ok());
}

/// 画面の縁は内側に入れる。縁を外に置くと、画面の端の1列で履歴が常に捨てられ、縁が他より粗く残る。
#[test]
fn 画面の縁は内側とみなす() {
    assert!(画面上の位置::生成する(-1.0, 1.0).unwrap().画面の内側か());
    assert!(画面上の位置::生成する(1.0, -1.0).unwrap().画面の内側か());
    assert!(!画面上の位置::生成する(1.0001, 0.0).unwrap().画面の内側か());
    assert!(!画面上の位置::生成する(0.0, -1.0001).unwrap().画面の内側か());
}

#[test]
fn エラーは項目と値を表示に含める() {
    let 表示 = format!("{}", 時間再構成エラー::値域外("線形色の成分", -1.0));
    assert!(表示.contains("線形色の成分"), "項目が表示に無い: {表示}");
    assert!(表示.contains("-1"), "値が表示に無い: {表示}");
}
