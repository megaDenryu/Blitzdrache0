//! 指数移動平均が寄与率のとおりに混ぜることを確かめる。担うのは、両端の寄与率で片方がそのまま残ること、
//! 中間で両者の間へ入ること、寄与率を上げるほど今のフレームへ寄ることである。
//!
//! 両端だけを見ると、寄与率を読まずに分岐で返す実装でも通ってしまう。中間の値が2つの色のちょうど内分点に
//! なることと、寄与率を変えると結果が動くことを対に置く。

#![allow(clippy::unwrap_used)]

use super::{今のフレームの寄与率, 指数移動平均で混ぜる, 線形色};

const 許容: f32 = 1.0e-6;

fn 履歴の色() -> 線形色 {
    線形色::生成する(0.2, 0.4, 0.8).unwrap()
}

fn 今の色() -> 線形色 {
    線形色::生成する(1.2, 0.0, 0.4).unwrap()
}

fn 混ぜる(寄与率: f32) -> [f32; 3] {
    指数移動平均で混ぜる(履歴の色(), 今の色(), 今のフレームの寄与率::生成する(寄与率).unwrap())
        .unwrap()
        .成分()
}

#[test]
fn 寄与率が零なら履歴がそのまま残る() {
    assert_eq!(混ぜる(0.0), 履歴の色().成分());
}

#[test]
fn 寄与率が一なら今のフレームがそのまま出る() {
    assert_eq!(混ぜる(1.0), 今の色().成分());
}

/// 寄与率を読まない実装はこの検査で落ちる。
#[test]
fn 中間の寄与率は成分ごとの内分点になる() {
    let 結果 = 混ぜる(0.25);
    let 履歴 = 履歴の色().成分();
    let 今 = 今の色().成分();
    for 位置 in 0..3 {
        let 期待 = 履歴[位置] * 0.75 + 今[位置] * 0.25;
        assert!((結果[位置] - 期待).abs() < 許容, "{位置}番目の成分が内分点でない: {}", 結果[位置]);
    }
}

/// 定数を返す実装はこの検査で落ちる。
#[test]
fn 寄与率を上げるほど今のフレームへ寄る() {
    let 履歴 = 履歴の色().成分();
    let 今 = 今の色().成分();
    let 弱い = 混ぜる(0.1);
    let 強い = 混ぜる(0.9);
    for 位置 in 0..3 {
        let 弱い隔たり = (弱い[位置] - 今[位置]).abs();
        let 強い隔たり = (強い[位置] - 今[位置]).abs();
        assert!(強い隔たり < 弱い隔たり, "{位置}番目の成分が寄与率で動かない");
        assert!((弱い[位置] - 履歴[位置]).abs() < (強い[位置] - 履歴[位置]).abs());
    }
}

#[test]
fn 寄与率は値域の外を拒む() {
    assert!(今のフレームの寄与率::生成する(-0.1).is_err());
    assert!(今のフレームの寄与率::生成する(1.1).is_err());
    assert!(今のフレームの寄与率::生成する(f32::NAN).is_err());
    assert!(今のフレームの寄与率::生成する(0.0).is_ok());
    assert!(今のフレームの寄与率::生成する(1.0).is_ok());
}

#[test]
fn 履歴の寄与率は今のフレームの寄与率の余りである() {
    let 寄与率 = 今のフレームの寄与率::生成する(0.3).unwrap();
    assert!((寄与率.履歴の寄与率() - 0.7).abs() < 許容);
    assert!((今のフレームの寄与率::既定().値() - 0.1).abs() < 許容);
}
