//! 1画素の再構成が、採否を見てから収め、収めてから混ぜる順で組み立てられていることを確かめる。
//!
//! 結果が「もっともらしい範囲へ入る」ことを見るだけでは、順を入れ替えた実装も採否を無視した実装も通ってしまう。
//! ここでは正しい順で組み立てた値との一致を見たうえで、入れ替えた順が別の値を出す場面であることを同じ検査の中で
//! 確かめる。場面の選び方が甘くて2つの順が一致していたら、一致を見る検査は何も反証していない。

#![allow(clippy::unwrap_used)]

use super::{
    一画素を再構成する, 今のフレームの寄与率, 履歴の採否, 指数移動平均で混ぜる, 線形色, 輝度で重み付けて混ぜる, 近傍の色の範囲
};

const 許容: f32 = 1.0e-6;

/// 履歴が近傍の範囲から大きく外れる場面。2つの順の違いが値に出るために、範囲の外側へ2桁離す。
fn 履歴の色() -> 線形色 {
    線形色::生成する(20.0, 20.0, 20.0).unwrap()
}

fn 今の色() -> 線形色 {
    線形色::生成する(0.1, 0.1, 0.1).unwrap()
}

fn 範囲() -> 近傍の色の範囲 {
    近傍の色の範囲::近傍から求める(&[線形色::生成する(0.1, 0.1, 0.1).unwrap(), 線形色::生成する(0.5, 0.5, 0.5).unwrap()]).unwrap()
}

fn 寄与率() -> 今のフレームの寄与率 {
    今のフレームの寄与率::生成する(0.5).unwrap()
}

fn 再構成する(採否: 履歴の採否) -> 線形色 {
    一画素を再構成する(今の色(), 履歴の色(), 範囲(), 採否, 寄与率()).unwrap()
}

/// 収めてから混ぜる正しい順。
fn 収めてから混ぜた色() -> 線形色 {
    輝度で重み付けて混ぜる(範囲().収める(履歴の色()).unwrap(), 今の色(), 寄与率()).unwrap()
}

/// 混ぜてから収める入れ替えた順。
fn 混ぜてから収めた色() -> 線形色 {
    範囲().収める(輝度で重み付けて混ぜる(履歴の色(), 今の色(), 寄与率()).unwrap()).unwrap()
}

/// 場面が2つの順を見分けられることを先に確かめる。これが無いと、下の一致の検査が何も反証しない。
#[test]
fn この場面では二つの合成順が別の色を出す() {
    let 隔たり = (収めてから混ぜた色().成分()[0] - 混ぜてから収めた色().成分()[0]).abs();
    assert!(隔たり > 0.1, "2つの合成順が近すぎて反証にならない(隔たり{隔たり})");
}

/// 混ぜてから収める実装はこの検査で落ちる。
#[test]
fn 履歴を採るときは収めてから混ぜる() {
    let 結果 = 再構成する(履歴の採否::採る).成分();
    let 期待 = 収めてから混ぜた色().成分();
    for 位置 in 0..3 {
        assert!(
            (結果[位置] - 期待[位置]).abs() < 許容,
            "{位置}番目の成分が合成順と食い違う: {}",
            結果[位置]
        );
    }
}

/// 収めを飛ばした実装と、輝度の重み付けを指数移動平均へ落とした実装が落ちることを見る。
#[test]
fn 採るときの結果は収めと輝度の重みの両方を通っている() {
    let 収めた履歴 = 範囲().収める(履歴の色()).unwrap();
    let 結果 = 再構成する(履歴の採否::採る).成分()[0];
    let 収めを飛ばした = 輝度で重み付けて混ぜる(履歴の色(), 今の色(), 寄与率()).unwrap().成分()[0];
    let 重みを外した = 指数移動平均で混ぜる(収めた履歴, 今の色(), 寄与率()).unwrap().成分()[0];
    assert!((結果 - 収めを飛ばした).abs() > 許容, "収めを通っていない");
    assert!((結果 - 重みを外した).abs() > 許容, "輝度の重みを通っていない");
}

/// 採否を無視して常に混ぜる実装はこの検査で落ちる。
#[test]
fn 捨てるときは今のフレームの色がそのまま出る() {
    assert_eq!(再構成する(履歴の採否::出現領域だから捨てる).成分(), 今の色().成分());
    assert_eq!(再構成する(履歴の採否::画面の外だから捨てる).成分(), 今の色().成分());
}

/// 常に今のフレームを返す実装はこの検査で落ちる。
#[test]
fn 採ると捨てるで結果が変わる() {
    let 採った = 再構成する(履歴の採否::採る).成分()[0];
    let 捨てた = 再構成する(履歴の採否::出現領域だから捨てる).成分()[0];
    assert!((採った - 捨てた).abs() > 許容, "採否が結果へ効いていない(採る{採った}・捨てる{捨てた})");
}

/// 履歴が既に近傍の範囲の内側にあるなら、再構成は収めを挟まない混合と一致する。
#[test]
fn 範囲の内側の履歴では収めが結果を変えない() {
    let 内側 = 線形色::生成する(0.3, 0.3, 0.3).unwrap();
    let 結果 = 一画素を再構成する(今の色(), 内側, 範囲(), 履歴の採否::採る, 寄与率()).unwrap();
    let 期待 = 輝度で重み付けて混ぜる(内側, 今の色(), 寄与率()).unwrap();
    assert_eq!(結果.成分(), 期待.成分());
}
