//! 明るさの圧縮より前の線形の色そのもの。担うのは3成分の有限性と負でないことの保証だけである。
//!
//! 表示可能範囲へ収まっていることを不変条件にしないのは、混合が明るさの圧縮より前で行われるためである。
//! ここで1に丸めると、明るい光源が履歴へ入るときに情報が落ち、圧縮の後で階調が潰れる。
//!
//! 放射輝度色と別の型にするのは、あちらが光の供給の側の量であり、こちらが画の完成の段で混ぜ合わせる
//! 画面上の色だからである。同じ型にすると、光源の強さと画面の色が同じ演算へ混ざっても型が止めない。

use super::error::時間再構成エラー;

/// 明るさの圧縮より前の線形RGB。
/// 不変条件: 3成分とも有限かつ0以上である。負の明るさは物理的にも描画的にも意味を持たない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 線形色 {
    成分: [f32; 3],
}

impl 線形色 {
    pub fn 生成する(赤: f32, 緑: f32, 青: f32) -> Result<Self, 時間再構成エラー> {
        let 成分 = [赤, 緑, 青];
        for 値 in 成分 {
            if !値.is_finite() || 値 < 0.0 {
                return Err(時間再構成エラー::値域外("線形色の成分", 値));
            }
        }
        Ok(Self { 成分 })
    }

    /// 3成分から作る。成分の並びは赤・緑・青である。
    pub fn 成分から生成する(成分: [f32; 3]) -> Result<Self, 時間再構成エラー> {
        Self::生成する(成分[0], 成分[1], 成分[2])
    }

    pub fn 成分(self) -> [f32; 3] {
        self.成分
    }
}
