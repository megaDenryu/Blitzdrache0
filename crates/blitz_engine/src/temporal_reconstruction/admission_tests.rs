//! 履歴の採否が、画面の外と出現領域を別の理由として見分けることを確かめる。担うのは、奥行きが揃えば採ること、
//! 大きく食い違えば出現領域とすること、画面の外は奥行きによらず捨てることである。
//!
//! 採る側と捨てる側の両方を対で置く。片方だけを見ると、常に採る実装と常に捨てる実装のどちらかが通ってしまう。
//! さらに、同じ絶対の食い違いが近くでは捨てられ遠くでは採られることを確かめ、許容が割合であることを反証する。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::{ビュー空間の奥行き, 出現領域の相対許容, 履歴の採否, 履歴を採るか判定する, 画面上の位置};

fn 奥行き(値: f32) -> ビュー空間の奥行き {
    ビュー空間の奥行き::生成する(メートル::生成する(値)).unwrap()
}

fn 画面の内側() -> 画面上の位置 {
    画面上の位置::生成する(0.25, -0.5).unwrap()
}

fn 判定する(前の奥行き: f32, 今の奥行き: f32) -> 履歴の採否 {
    履歴を採るか判定する(画面の内側(), 奥行き(前の奥行き), 奥行き(今の奥行き), 出現領域の相対許容::既定())
}

#[test]
fn 奥行きが揃えば履歴を採る() {
    assert_eq!(判定する(20.0, 20.0), 履歴の採否::採る);
    assert_eq!(判定する(20.5, 20.0), 履歴の採否::採る);
}

#[test]
fn 奥行きが大きく食い違えば出現領域とする() {
    assert_eq!(判定する(2.0, 20.0), 履歴の採否::出現領域だから捨てる);
    assert_eq!(判定する(60.0, 20.0), 履歴の採否::出現領域だから捨てる);
}

/// 許容の境界の内と外で判定が変わることを見る。常に採る実装も常に捨てる実装もここで落ちる。
#[test]
fn 許容の境界の内と外で判定が変わる() {
    let 許容 = 出現領域の相対許容::生成する(0.1).unwrap();
    let 内 = 履歴を採るか判定する(画面の内側(), 奥行き(10.9), 奥行き(10.0), 許容);
    let 外 = 履歴を採るか判定する(画面の内側(), 奥行き(11.1), 奥行き(10.0), 許容);
    assert_eq!(内, 履歴の採否::採る);
    assert_eq!(外, 履歴の採否::出現領域だから捨てる);
}

/// 絶対の長さで比べる実装はこの検査で落ちる。同じ3メートルの食い違いが、近くでは出現領域になり遠くでは同じ面になる。
#[test]
fn 同じ食い違いでも奥行きが遠いほど許される() {
    assert_eq!(判定する(13.0, 10.0), 履歴の採否::出現領域だから捨てる);
    assert_eq!(判定する(103.0, 100.0), 履歴の採否::採る);
}

/// 画面の外は奥行きが完全に一致していても捨てる。奥行きの照合を先に置いた実装はここで落ちる。
#[test]
fn 画面の外は奥行きによらず捨てる() {
    let 外 = 画面上の位置::生成する(1.5, 0.0).unwrap();
    let 判定 = 履歴を採るか判定する(外, 奥行き(20.0), 奥行き(20.0), 出現領域の相対許容::既定());
    assert_eq!(判定, 履歴の採否::画面の外だから捨てる);
}

#[test]
fn 奥行きは正でない値と非有限を拒む() {
    assert!(ビュー空間の奥行き::生成する(メートル::生成する(0.0)).is_err());
    assert!(ビュー空間の奥行き::生成する(メートル::生成する(-1.0)).is_err());
    assert!(ビュー空間の奥行き::生成する(メートル::生成する(f32::INFINITY)).is_err());
    assert!(ビュー空間の奥行き::生成する(メートル::生成する(0.1)).is_ok());
}

#[test]
fn 相対許容は値域の外を拒む() {
    assert!(出現領域の相対許容::生成する(0.0).is_err());
    assert!(出現領域の相対許容::生成する(1.0).is_err());
    assert!(出現領域の相対許容::生成する(f32::NAN).is_err());
    assert!(出現領域の相対許容::生成する(0.05).is_ok());
}
