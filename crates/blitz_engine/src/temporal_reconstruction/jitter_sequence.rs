//! 決定的な低食い違い列(ハルトン列)から、その添字の標本位置を求める工程。受け取るのは列の添字、
//! 返すのは画素を単位とするずらしである。
//!
//! 乱数でなく決定的な列を採るのは、同じフレーム番号からは必ず同じ絵が出ることが検収の前提だからである。
//! 一様乱数でなく低食い違い列を採るのは、少ない標本数でも画素の中が偏りなく埋まるためである。
//!
//! ハルトン列の添字は1から始める。0番目の桁の反転は全ての基数で0になり、横も縦も画素の受け持つ範囲の
//! ちょうど端へ落ちて、1つの標本が無駄になる。

use super::constants::{横の基数, 縦の基数};
use super::error::時間再構成エラー;
use super::pixel_offset::画素を単位とするずらし;
use super::sequence_index::ずらしの列の添字;

pub fn 画素を単位とするずらしを求める(
    添字: ずらしの列の添字
) -> Result<画素を単位とするずらし, 時間再構成エラー> {
    let ハルトンの添字 = ハルトンの添字へ写す(添字);
    画素を単位とするずらし::生成する(
        桁を反転した小数を求める(ハルトンの添字, 横の基数) - 0.5,
        桁を反転した小数を求める(ハルトンの添字, 縦の基数) - 0.5,
    )
}

/// 0から始まる列の添字を、1から始まるハルトン列の添字へ写す。
/// 注意: 列の長さが16ビットに収まらない値へ育てば、この変換が破れて標本位置が別の添字のものへ化ける。
fn ハルトンの添字へ写す(添字: ずらしの列の添字) -> u16 {
    let 番号 = 添字.値() + 1;
    u16::try_from(番号).unwrap_or_else(|_| panic!("ハルトン列の添字{番号}がu16に収まらない"))
}

/// 添字をその基数で表したときの桁を並べ替え、小数点の右側へ逆順に置いた値。0以上1未満になる。
///
/// 単精度で組み立てるのは、段3bで入るslangの写しが単精度で同じ列を作るためである。倍精度で作ってから
/// 狭めると、丸めの位置が写しと1つずれる。
fn 桁を反転した小数を求める(添字: u16, 基数: u16) -> f32 {
    let 基数の実数 = f32::from(基数);
    let mut 残り = 添字;
    let mut 桁の重み = 1.0 / 基数の実数;
    let mut 結果 = 0.0;
    while 残り > 0 {
        結果 += f32::from(残り % 基数) * 桁の重み;
        残り /= 基数;
        桁の重み /= 基数の実数;
    }
    結果
}
