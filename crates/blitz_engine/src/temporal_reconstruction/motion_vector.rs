//! 動きベクトルの規約そのものを型として固定するもの。担うのは、向き・単位・画素内ずらしの差分の含否の3つを
//! 生成と変換の形で言い切ることと、2成分の有限性の保証である。
//!
//! この3つを実装のどれよりも先に決めるのは、後から変えると書く側(シーン描画と空のパス)と読む側(履歴の参照と棄却)の
//! 全てへ波及するためである。値の意味が型に現れていない状態でどちらかを先に書くと、符号の取り違えが絵の上でしか
//! 見つからなくなる。
//! 参照: `_doc/設計/時間再構成.md`「判断f: 純関数層の中身」
//!
//! 向きは、今のフレームの画素から前のフレームの位置へ向かう。再構成が履歴を参照する向きそのものであり、
//! 読む側が符号を反転せずにそのまま足せる。
//!
//! 単位は正規化装置座標の差分である。画素内ずらしと同じ座標であり、画面の画素数に依存する量が
//! 画素との換算の1箇所だけに閉じる。
//!
//! 画素内ずらしの差分は含めない。ずらしは同じ対象を標本する位置の揺れであって対象の移動ではないため、
//! これを含めると静止した世界で静止したカメラでも動きベクトルが零にならず、棄却の判定が毎フレーム揺れる。
//! 前のフレームのビュー射影をずらし無しで渡す判断bと同じ理由による。

use super::error::時間再構成エラー;
use super::screen_position::画面上の位置;

/// 今のフレームの画素から前のフレームの位置へ向かう、正規化装置座標での差分。
/// 不変条件: 2成分とも有限である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 動きベクトル {
    正規化装置座標の横: f32,
    正規化装置座標の縦: f32,
}

impl 動きベクトル {
    pub fn 生成する(正規化装置座標の横: f32, 正規化装置座標の縦: f32) -> Result<Self, 時間再構成エラー> {
        if !正規化装置座標の横.is_finite() {
            return Err(時間再構成エラー::値域外("動きベクトルの横", 正規化装置座標の横));
        }
        if !正規化装置座標の縦.is_finite() {
            return Err(時間再構成エラー::値域外("動きベクトルの縦", 正規化装置座標の縦));
        }
        Ok(Self {
            正規化装置座標の横,
            正規化装置座標の縦,
        })
    }

    /// 前のフレームでも同じ位置に見えていた画素の値。静止した世界を静止したカメラで見たときの全画素がこれになる。
    pub fn 動いていない() -> Self {
        Self {
            正規化装置座標の横: 0.0,
            正規化装置座標の縦: 0.0,
        }
    }

    /// 2つの位置から作る。向きの規約がこの引き算の順に現れており、書く側はこれと同じ順で作る。
    pub fn 二つの位置から求める(
        今のフレームの位置: 画面上の位置,
        前のフレームの位置: 画面上の位置,
    ) -> Result<Self, 時間再構成エラー> {
        Self::生成する(
            前のフレームの位置.横() - 今のフレームの位置.横(),
            前のフレームの位置.縦() - 今のフレームの位置.縦(),
        )
    }

    pub fn 正規化装置座標の横(self) -> f32 {
        self.正規化装置座標の横
    }

    pub fn 正規化装置座標の縦(self) -> f32 {
        self.正規化装置座標の縦
    }

    /// その画素が前のフレームで居た位置。履歴を参照する側は、この1つの変換だけを使う。
    pub fn 前のフレームの位置(
        self, 今のフレームの位置: 画面上の位置
    ) -> Result<画面上の位置, 時間再構成エラー> {
        画面上の位置::生成する(
            今のフレームの位置.横() + self.正規化装置座標の横,
            今のフレームの位置.縦() + self.正規化装置座標の縦,
        )
    }
}
