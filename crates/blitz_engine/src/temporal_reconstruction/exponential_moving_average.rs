//! 履歴と今のフレームを固定の割合で混ぜる工程。受け取るのは履歴の色・今のフレームの色・今のフレームの寄与率、
//! 返すのは混ぜた色である。
//!
//! 過去のフレームを何枚も保持して平均を取り直すのでなく、1枚の履歴へ畳み込むのは、必要な記憶が履歴画像1枚で
//! 済み、しかも古いフレームほど寄与が幾何級数で小さくなるためである。実効の平均窓は寄与率の逆数のフレーム数になる。
//!
//! 3つの混合の中でこれが土台であり、近傍の色による収めと輝度による重み付けは、この土台の入力または重みへ
//! 手を入れる形で重ねる。

use super::current_frame_ratio::今のフレームの寄与率;
use super::error::時間再構成エラー;
use super::linear_color::線形色;

/// 注意: 成分ごとに2つの積を先に丸め、その和を採る、この演算の順そのものが段3bで入るslangの写しとの一致契約である。
/// 積和融合を使うと結果が写しと最下位の桁で食い違い、合成した入力の注入による突き合わせの許容を誤差が食い潰す。
pub fn 指数移動平均で混ぜる(
    履歴: 線形色,
    今のフレーム: 線形色,
    寄与率: 今のフレームの寄与率,
) -> Result<線形色, 時間再構成エラー> {
    let 履歴の成分 = 履歴.成分();
    let 今の成分 = 今のフレーム.成分();
    let 履歴の割合 = 寄与率.履歴の寄与率();
    let 今の割合 = 寄与率.値();
    線形色::生成する(
        履歴の成分[0] * 履歴の割合 + 今の成分[0] * 今の割合,
        履歴の成分[1] * 履歴の割合 + 今の成分[1] * 今の割合,
        履歴の成分[2] * 履歴の割合 + 今の成分[2] * 今の割合,
    )
}
