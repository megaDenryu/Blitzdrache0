//! 近傍の色による収めが、範囲の外の履歴だけを動かすことを確かめる。担うのは、外の色が範囲の端まで落ちること、
//! 内の色が1つも動かないこと、近傍が空なら型付きの失敗になることである。
//!
//! 外が落ちることだけを見ると、常に近傍の平均を返す実装でも通ってしまう。内の色がそのまま返ることを対に置く。

#![allow(clippy::unwrap_used)]

use super::{線形色, 近傍の色の範囲};

const 許容: f32 = 1.0e-6;

fn 近傍() -> Vec<線形色> {
    vec![
        線形色::生成する(0.2, 0.5, 1.0).unwrap(),
        線形色::生成する(0.4, 0.1, 2.0).unwrap(),
        線形色::生成する(0.3, 0.9, 1.5).unwrap(),
    ]
}

fn 範囲() -> 近傍の色の範囲 {
    近傍の色の範囲::近傍から求める(&近傍()).unwrap()
}

#[test]
fn 範囲は近傍の成分ごとの最小と最大である() {
    assert_eq!(範囲().最小().成分(), [0.2, 0.1, 1.0]);
    assert_eq!(範囲().最大().成分(), [0.4, 0.9, 2.0]);
}

#[test]
fn 範囲より上の履歴は上端まで落ちる() {
    let 収めた = 範囲().収める(線形色::生成する(9.0, 5.0, 8.0).unwrap()).unwrap();
    assert_eq!(収めた.成分(), 範囲().最大().成分());
}

#[test]
fn 範囲より下の履歴は下端まで上がる() {
    let 収めた = 範囲().収める(線形色::生成する(0.0, 0.0, 0.0).unwrap()).unwrap();
    assert_eq!(収めた.成分(), 範囲().最小().成分());
}

/// 常に範囲の端や平均を返す実装はこの検査で落ちる。
#[test]
fn 範囲の内側の履歴は動かない() {
    let 内側 = 線形色::生成する(0.35, 0.2, 1.7).unwrap();
    let 収めた = 範囲().収める(内側).unwrap();
    assert_eq!(収めた.成分(), 内側.成分());
}

/// 成分ごとに独立して収めることを、1成分だけが外にある色で確かめる。
#[test]
fn 外にある成分だけが動く() {
    let 収めた = 範囲().収める(線形色::生成する(0.35, 4.0, 1.7).unwrap()).unwrap();
    assert!((収めた.成分()[0] - 0.35).abs() < 許容);
    assert!((収めた.成分()[1] - 0.9).abs() < 許容);
    assert!((収めた.成分()[2] - 1.7).abs() < 許容);
}

#[test]
fn 近傍が空なら失敗する() {
    assert!(近傍の色の範囲::近傍から求める(&[]).is_err());
    assert!(近傍の色の範囲::近傍から求める(&[線形色::生成する(0.5, 0.5, 0.5).unwrap()]).is_ok());
}

/// 近傍が1色だけなら範囲は幅を持たず、どんな履歴もその色へ落ちる。
#[test]
fn 一色だけの近傍は履歴をその色へ落とす() {
    let 一色 = 線形色::生成する(0.5, 0.25, 0.125).unwrap();
    let 範囲 = 近傍の色の範囲::近傍から求める(&[一色]).unwrap();
    assert_eq!(範囲.収める(線形色::生成する(3.0, 0.0, 1.0).unwrap()).unwrap().成分(), 一色.成分());
}

#[test]
fn 線形色は非有限と負を拒む() {
    assert!(線形色::生成する(f32::NAN, 0.0, 0.0).is_err());
    assert!(線形色::生成する(0.0, -0.1, 0.0).is_err());
    assert!(線形色::生成する(0.0, 0.0, f32::INFINITY).is_err());
    assert!(線形色::生成する(0.0, 0.0, 1000.0).is_ok());
}
