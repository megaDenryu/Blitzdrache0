//! 検査が共有する設定と状態の組み立て。基準距離50メートル・ヒステリシス幅5メートルという本番と同じ値を持つ。

use blitz_math::メートル;

use crate::{個体LOD選択設定, 個体別段状態, 個体詳細段};

pub(super) const 基準距離: f32 = 50.0;
pub(super) const ヒステリシス幅: f32 = 5.0;

pub(super) fn 設定() -> 個体LOD選択設定 {
    個体LOD選択設定::生成する(メートル::生成する(基準距離), メートル::生成する(ヒステリシス幅)).unwrap()
}

pub(super) fn 状態(個体数: usize, 段数: usize) -> 個体別段状態 {
    個体別段状態::生成する(個体数, 段数).unwrap()
}

/// 個体0の段を距離から引く。1体だけの状態を使う検査が繰り返し呼ぶ。
pub(super) fn 段(状態: &mut 個体別段状態, 距離: f32) -> 個体詳細段 {
    状態.段を決める(0, メートル::生成する(距離), 設定())
}

pub(super) fn 段番号(状態: &mut 個体別段状態, 距離: f32) -> u8 {
    段(状態, 距離).番号()
}
