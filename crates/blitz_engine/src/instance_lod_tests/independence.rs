//! 個体ごとの独立の検査。同じ群の中で個体ごとに違う段が同時に立つこと、
//! 前回の段の記憶が個体ごとに分かれていること、設定の検証が破れを拒むことを確かめる。

use blitz_math::メートル;

use crate::{個体LODエラー, 個体LOD選択設定};

use super::fixture::{ヒステリシス幅, 基準距離, 状態, 設定};

#[test]
fn 同じ群の個体が距離に応じて別々の段になる() {
    let mut 状態 = 状態(3, 3);
    let 距離一覧 = [10.0, 60.0, 120.0];
    let 段一覧: Vec<u8> = 距離一覧
        .into_iter()
        .enumerate()
        .map(|(添字, 距離)| 状態.段を決める(添字, メートル::生成する(距離), 設定()).番号())
        .collect();
    assert_eq!(段一覧, vec![0, 1, 2]);
}

/// 個体0を帯の内側で往復させても、個体1の記憶は個体0の履歴に影響されない。
#[test]
fn 前回の段の記憶は個体ごとに分かれる() {
    let mut 状態 = 状態(2, 2);
    assert_eq!(状態.段を決める(0, メートル::生成する(0.0), 設定()).番号(), 0);
    assert_eq!(状態.段を決める(1, メートル::生成する(基準距離 + ヒステリシス幅 + 1.0), 設定()).番号(), 1);
    // 同じ距離を与えても、個体0は段0を保ち個体1は段1を保つ。
    assert_eq!(状態.段を決める(0, メートル::生成する(基準距離), 設定()).番号(), 0);
    assert_eq!(状態.段を決める(1, メートル::生成する(基準距離), 設定()).番号(), 1);
    assert_eq!(状態.切替回数(), 0);
}

#[test]
fn 状態は個体数と段数を覚えている() {
    let 状態 = 状態(7, 3);
    assert_eq!(状態.個体数(), 7);
    assert_eq!(状態.段数(), 3);
}

#[test]
fn 基準距離が正でない設定は拒む() {
    let 結果 = 個体LOD選択設定::生成する(メートル::生成する(0.0), メートル::生成する(1.0));
    assert_eq!(結果.err(), Some(個体LODエラー::基準距離不正));
}

#[test]
fn ヒステリシス幅が基準距離の半分以上の設定は拒む() {
    let 結果 = 個体LOD選択設定::生成する(メートル::生成する(10.0), メートル::生成する(5.0));
    assert_eq!(結果.err(), Some(個体LODエラー::ヒステリシス幅過大));
}
