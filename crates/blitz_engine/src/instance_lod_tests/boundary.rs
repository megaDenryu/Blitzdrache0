//! 距離の境界値とヒステリシス帯の検査。初回の床関数、基準距離ちょうど、帯の内側の往復、段数上限での飽和を確かめる。

use super::fixture::{ヒステリシス幅, 基準距離, 段番号, 状態};

#[test]
fn 初回は基準距離の床関数で段が決まる() {
    for (距離, 期待段) in [(0.0, 0), (49.9, 0), (50.0, 1), (99.9, 1), (100.0, 2), (149.9, 2)] {
        let mut 状態 = 状態(1, 4);
        assert_eq!(段番号(&mut 状態, 距離), 期待段, "距離{距離}");
    }
}

/// 基準距離ちょうどは1段粗い側である。比較演算子が`>`へ弱まると段0になる。
#[test]
fn 距離が基準距離ちょうどなら初回は1段粗い側になる() {
    let mut 状態 = 状態(1, 2);
    assert_eq!(段番号(&mut 状態, 基準距離), 1);
}

#[test]
fn ヒステリシス帯の内側では前回の段を保つ() {
    let 帯の内側 = [基準距離 - ヒステリシス幅 + 1.0, 基準距離, 基準距離 + ヒステリシス幅 - 1.0];

    let mut 細かいまま = 状態(1, 2);
    assert_eq!(段番号(&mut 細かいまま, 基準距離 - ヒステリシス幅 - 1.0), 0);
    for 距離 in 帯の内側 {
        assert_eq!(段番号(&mut 細かいまま, 距離), 0, "距離{距離}で段0を保つ");
    }

    let mut 粗いまま = 状態(1, 2);
    assert_eq!(段番号(&mut 粗いまま, 基準距離 + ヒステリシス幅 + 1.0), 1);
    for 距離 in 帯の内側 {
        assert_eq!(段番号(&mut 粗いまま, 距離), 1, "距離{距離}で段1を保つ");
    }
}

/// 帯の内側を何度往復しても段が入れ替わらないことを、切替回数が0のままであることで示す。
#[test]
fn 帯の内側の往復では段が振動しない() {
    let mut 状態 = 状態(1, 2);
    assert_eq!(段番号(&mut 状態, 基準距離 - 1.0), 0);
    for _ in 0..8 {
        段番号(&mut 状態, 基準距離 + 1.0);
        段番号(&mut 状態, 基準距離 - 1.0);
    }
    assert_eq!(状態.切替回数(), 0, "帯の内側の往復で段が入れ替わった");
}

/// 粗い側へ進むのは境界にヒステリシス幅を足した値を「超えた」ときであり、ちょうどの値では進まない。
#[test]
fn 粗い側の境界ちょうどでは段を保つ() {
    let mut 状態 = 状態(1, 2);
    assert_eq!(段番号(&mut 状態, 0.0), 0);
    assert_eq!(段番号(&mut 状態, 基準距離 + ヒステリシス幅), 0);
}

/// 細かい側へ戻すのは境界からヒステリシス幅を引いた値を「下回った」ときであり、ちょうどの値では戻らない。
#[test]
fn 細かい側の境界ちょうどでは段を保つ() {
    let mut 状態 = 状態(1, 2);
    assert_eq!(段番号(&mut 状態, 基準距離 + ヒステリシス幅 + 1.0), 1);
    assert_eq!(段番号(&mut 状態, 基準距離 - ヒステリシス幅), 1);
}

#[test]
fn 帯を越えると粗い側へ進み戻ると細かい側へ戻る() {
    let mut 状態 = 状態(1, 2);
    assert_eq!(段番号(&mut 状態, 0.0), 0);
    assert_eq!(段番号(&mut 状態, 基準距離 + ヒステリシス幅 + 0.5), 1);
    assert_eq!(段番号(&mut 状態, 基準距離 - ヒステリシス幅 - 0.5), 0);
    assert_eq!(状態.切替回数(), 2);
}

/// 段数が2の原型では、どれだけ遠くても段1で止まる。
#[test]
fn 段数の上限で飽和する() {
    let mut 初回 = 状態(1, 2);
    assert_eq!(段番号(&mut 初回, 基準距離 * 100.0), 1);

    let mut 前回あり = 状態(1, 2);
    assert_eq!(段番号(&mut 前回あり, 0.0), 0);
    assert_eq!(段番号(&mut 前回あり, 基準距離 * 100.0), 1);
}
