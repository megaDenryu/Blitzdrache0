use blitz_render::フレーム段階;

use crate::既定フレーム構成を作る;

#[test]
fn ポスト処理の有無だけを切り替える() {
    let ポストあり = 既定フレーム構成を作る(true);
    let ポストなし = 既定フレーム構成を作る(false);

    assert!(ポストあり.含む(フレーム段階::ブルームとトーンマップ));
    assert!(!ポストなし.含む(フレーム段階::ブルームとトーンマップ));
    assert!(ポストあり.含む(フレーム段階::影));
    assert!(ポストなし.含む(フレーム段階::影));
}
