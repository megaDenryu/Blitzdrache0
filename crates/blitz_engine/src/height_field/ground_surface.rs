//! 世界の地表の面: 高さ場の1点で読んだ、描画が実際に張る三角形の平面である。
//! 持つのは地表そのものの大域位置と、上向きの単位法線と、東と南それぞれへ進む向きの単位接線と、どの三角形に
//! 乗っていたかの所在である。
//!
//! 高さだけの問い合わせと同じ1つの工程からこの値を作るのは、三角形の選び方を2つ持つと、高さを求めた三角形と
//! 法線を求めた三角形が食い違い、面に乗っていない足元が生まれるためである。

use blitz_math::{ワールド, 大域ワールド位置, 方向};

use super::triangle_location::地表の三角形の所在;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 世界の地表の面 {
    地表の大域位置: 大域ワールド位置,
    上向きの単位法線: 方向<ワールド>,
    東向きの単位接線: 方向<ワールド>,
    南向きの単位接線: 方向<ワールド>,
    所在: 地表の三角形の所在,
}

impl 世界の地表の面 {
    pub fn 生成する(
        地表の大域位置: 大域ワールド位置,
        上向きの単位法線: 方向<ワールド>,
        東向きの単位接線: 方向<ワールド>,
        南向きの単位接線: 方向<ワールド>,
        所在: 地表の三角形の所在,
    ) -> Self {
        Self {
            地表の大域位置,
            上向きの単位法線,
            東向きの単位接線,
            南向きの単位接線,
            所在,
        }
    }

    /// 問い合わせた水平位置に、その点の地表高さを縦成分として入れた大域位置。
    pub fn 地表の大域位置(&self) -> 大域ワールド位置 {
        self.地表の大域位置
    }

    pub fn 上向きの単位法線(&self) -> 方向<ワールド> {
        self.上向きの単位法線
    }

    pub fn 東向きの単位接線(&self) -> 方向<ワールド> {
        self.東向きの単位接線
    }

    pub fn 南向きの単位接線(&self) -> 方向<ワールド> {
        self.南向きの単位接線
    }

    pub fn 所在(&self) -> 地表の三角形の所在 {
        self.所在
    }
}
