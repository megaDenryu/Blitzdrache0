//! 地表高さの問い合わせに対する答え。高さ場を持たない世界と、高さ場の広がりの外を別々の枝で表す。
//!
//! 枝で表すのは、どちらの場合も「高さが分からない」ことを呼び出し側が知る必要があり、0メートルを返すと
//! 標高0の平地と区別できなくなるためである。

use blitz_math::大域メートル;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 地表高さの問い合わせ結果 {
    /// 高さ場アセットをカタログに持たない世界。地形の高さという概念がその起動に存在しない。
    高さ場を持たない世界,
    /// 高さ場は持つが、問い合わせた水平位置がその広がりの外にある。
    高さ場の広がりの外,
    /// 高さ場から求めた地表高さ。
    地表高さ(大域メートル),
}
