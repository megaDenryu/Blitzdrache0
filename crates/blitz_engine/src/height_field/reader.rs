//! 実行中に地形の高さを問い合わせる口。高さ場を保持し、大域の水平位置を受けて地表高さを返す。
//! 高さ場を持たない世界を枝で持つため、問い合わせの戻り値も呼び出し側の型も「無し」で汚れない。
//! 参照: `_doc/設計/機能配置の指針.md`の所有者表「地形の高さの実行時参照」

use blitz_math::{大域メートル, 大域ワールド位置};

use super::field::高さ場;
use super::ground_surface_query_result::地表の面の問い合わせ結果;
use super::load_error::高さ場読込エラー;
use super::query_result::地表高さの問い合わせ結果;
use super::segment_query_result::線分が最初に当たる地表の問い合わせ結果;
use super::stable_id::世界の高さ場の安定IDの綴り;
use crate::asset::{アセットID, カタログ, 実行時形式から高さ場を読む, 実行時形式のファイル};

#[derive(Debug, Clone, PartialEq)]
pub enum 高さ場の読み口 {
    高さ場を持たない世界, // 検収用の世界と、地形を持たない起動がここへ落ちる
    高さ場を持つ世界(高さ場),
}

impl 高さ場の読み口 {
    /// カタログから世界の高さ場を読む。安定IDの登録が無い世界は「高さ場を持たない世界」になる。
    /// 登録があってファイルが読めない、あるいは形式が壊れている場合は型付きエラーにする。無言で持たない世界へ落とすと、
    /// 高さ場を焼いたはずの世界でキツネが地面へ沈む理由が読み取れなくなるためである。
    pub fn カタログから読み込む(カタログ: &カタログ) -> Result<Self, 高さ場読込エラー> {
        let id = アセットID::生成する(世界の高さ場の安定IDの綴り)?;
        let Some(パス) = カタログ.パスを参照する(&id) else {
            return Ok(Self::高さ場を持たない世界);
        };
        let ファイル = 実行時形式のファイル::パスから作る(パス.to_path_buf());
        Ok(Self::高さ場を持つ世界(実行時形式から高さ場を読む(
            &ファイル.バイト列を読む()?,
        )?))
    }

    pub fn 大域の水平位置から地表高さを求める(&self, 位置: 大域ワールド位置) -> 地表高さの問い合わせ結果 {
        let Self::高さ場を持つ世界(高さ場) = self else {
            return 地表高さの問い合わせ結果::高さ場を持たない世界;
        };
        match 高さ場.大域の水平位置から地表高さを求める(位置) {
            Ok(高さ) => 地表高さの問い合わせ結果::地表高さ(高さ),
            Err(_) => 地表高さの問い合わせ結果::高さ場の広がりの外,
        }
    }

    /// 地表の面(地表の大域位置・上向きの単位法線・2方向の単位接線・どの升目のどちらの三角形か)を求める。
    /// 高さだけを要る呼び出しと同じ工程を通るため、返る高さと法線は必ず同じ三角形の平面のものである。
    pub fn 大域の水平位置から地表の面を求める(&self, 位置: 大域ワールド位置) -> 地表の面の問い合わせ結果 {
        let Self::高さ場を持つ世界(高さ場) = self else {
            return 地表の面の問い合わせ結果::高さ場を持たない世界;
        };
        match 高さ場.大域の水平位置から地表の面を求める(位置) {
            Ok(面) => 地表の面の問い合わせ結果::地表の面(面),
            Err(_) => 地表の面の問い合わせ結果::高さ場の広がりの外,
        }
    }

    /// 始点から終点へ引いた線分が最初に当たる地表を求める。カメラのめり込み防止(視点と注視点の間の遮蔽)と、
    /// キャラクターの移動が最初の利用者である。高さ場の広がりの外へ出たことは枝でなく答えの完全性が表す。
    pub fn 線分が最初に当たる地表を求める(
        &self,
        始点: 大域ワールド位置,
        終点: 大域ワールド位置,
    ) -> 線分が最初に当たる地表の問い合わせ結果 {
        let Self::高さ場を持つ世界(高さ場) = self else {
            return 線分が最初に当たる地表の問い合わせ結果::高さ場を持たない世界;
        };
        match 高さ場.線分が最初に当たる地表を求める(始点, 終点) {
            Ok(答え) => 線分が最初に当たる地表の問い合わせ結果::線分を評価した結果(答え),
            Err(誤り) => 線分が最初に当たる地表の問い合わせ結果::線分を評価できない(誤り),
        }
    }

    pub fn 世界の中心の水平位置(&self) -> Option<大域ワールド位置> {
        let Self::高さ場を持つ世界(高さ場) = self else {
            return None;
        };
        let 諸元 = 高さ場.諸元();
        let 間隔 = f64::from(諸元.格子間隔().値());
        let 東 = 諸元.格子原点の東成分().値() + 間隔 * f64::from(諸元.東方向の格子点数() - 1) * 0.5;
        let 南 = 諸元.格子原点の南成分().値() + 間隔 * f64::from(諸元.南方向の格子点数() - 1) * 0.5;
        Some(大域ワールド位置::生成する(
            大域メートル::生成する(東),
            大域メートル::生成する(0.0),
            大域メートル::生成する(南),
        ))
    }
}
