//! 大域の水平位置を、それが属する升目の左手前の格子添字と升目の中の比へ写す工程。担当するのはこの写像だけであり、
//! 標本の保持も格子添字での読み出しも面の計算も持たない。
//!
//! 升目の中をどう埋めるかはこの工程の担当ではない。埋め方の正本は`blitz_collision`の区分線形にあり、
//! 描画が実際に張る2つの三角形の平面をそのまま使う。

use blitz_math::大域ワールド位置;

use super::error::高さ場の広がりの外エラー;
use super::grid_index::実数添字の床を格子添字へ変換する;
use super::specification::高さ場諸元;

/// 問い合わせ位置が属する升目の左手前の格子添字と、その升目の中での比。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 升目の中の位置 {
    pub(super) 東添字: u32,
    pub(super) 南添字: u32,
    pub(super) 東の比: f64,
    pub(super) 南の比: f64,
}

pub(super) fn 大域の水平位置を升目の中の位置へ写す(
    諸元: 高さ場諸元,
    位置: 大域ワールド位置,
) -> Result<升目の中の位置, 高さ場の広がりの外エラー> {
    let 東の大域メートル = 位置.x().値();
    let 南の大域メートル = 位置.z().値();
    let 範囲の外 = 高さ場の広がりの外エラー {
        東の大域メートル,
        南の大域メートル,
    };
    let 格子間隔 = f64::from(諸元.格子間隔().値());
    let 東の実数添字 = (東の大域メートル - 諸元.格子原点の東成分().値()) / 格子間隔;
    let 南の実数添字 = (南の大域メートル - 諸元.格子原点の南成分().値()) / 格子間隔;
    let (東添字, 東の比) = 軸ごとの升目の添字と比を求める(東の実数添字, 諸元.東方向の格子点数()).ok_or(範囲の外)?;
    let (南添字, 南の比) = 軸ごとの升目の添字と比を求める(南の実数添字, 諸元.南方向の格子点数()).ok_or(範囲の外)?;
    Ok(升目の中の位置 {
        東添字,
        南添字,
        東の比,
        南の比,
    })
}

/// 1つの軸について、実数添字を升目の左端の格子添字と升目の中の比へ分ける。
/// 最後の格子点ちょうどは1つ手前の升目の右端として扱う。そうしないと格子の縁だけが問い合わせに答えられない。
fn 軸ごとの升目の添字と比を求める(実数添字: f64, 格子点数: u32) -> Option<(u32, f64)> {
    let 上限の添字 = 格子点数.checked_sub(1)?;
    if !(0.0..=f64::from(上限の添字)).contains(&実数添字) {
        return None;
    }
    let 床 = 実数添字の床を格子添字へ変換する(実数添字)?;
    let 升目の添字 = 床.min(上限の添字.checked_sub(1)?);
    Some((升目の添字, 実数添字 - f64::from(升目の添字)))
}
