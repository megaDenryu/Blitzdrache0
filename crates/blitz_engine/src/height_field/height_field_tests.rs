//! 高さ場の生成の検証・格子点の参照・格子点の間の値・広がりの外の拒否を反証する。
//! 区分線形が双一次と違うことと、地表の面の問い合わせは`ground_surface_tests`が持つ。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};

use super::{地表高さの問い合わせ結果, 高さ場, 高さ場の読み口, 高さ場エラー, 高さ場諸元};

/// 東3点・南2点の高さ場。格子原点は東10メートル・南-20メートル、格子間隔は2メートルである。
pub(crate) fn 検査用の高さ場を作る() -> 高さ場 {
    let 諸元 = 高さ場諸元::生成する(大域メートル::生成する(10.0), 大域メートル::生成する(-20.0), メートル::生成する(2.0), 3, 2).unwrap();
    let 高さ一覧 = [1.0, 2.0, 3.0, 5.0, 6.0, 7.0].map(メートル::生成する).to_vec();
    高さ場::生成する(諸元, 高さ一覧).unwrap()
}

pub(super) fn 水平位置(東: f64, 南: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(東), 大域メートル::生成する(0.0), 大域メートル::生成する(南))
}

#[test]
fn 格子点数が2未満の諸元を拒む() {
    let 結果 = 高さ場諸元::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(0.0), メートル::生成する(1.0), 1, 4);
    assert_eq!(結果, Err(高さ場エラー::格子点数不足 { 東方向: 1, 南方向: 4 }));
}

#[test]
fn 標本数が諸元と合わない高さ場を拒む() {
    let 諸元 = 検査用の高さ場を作る().諸元();
    let 結果 = 高さ場::生成する(諸元, vec![メートル::生成する(0.0); 5]);
    assert_eq!(結果, Err(高さ場エラー::標本数不一致 { 期待: 6, 実際: 5 }));
}

/// 標本の高さの絶対値へ上限を課すのは、隣り合う升目が共有辺の上で返す高さの差の上界がその条件のもとで
/// 成り立つためである。上限を越えた標本を含む高さ場を拒むことを見る。
#[test]
fn 上限を越えた高さの標本を含む高さ場を拒む() {
    let 諸元 = 検査用の高さ場を作る().諸元();
    let mut 高さ一覧 = vec![メートル::生成する(0.0); 6];
    高さ一覧[2] = メートル::生成する(3.0e7);
    assert_eq!(高さ場::生成する(諸元, 高さ一覧), Err(高さ場エラー::高さの絶対値が上限を越えている));
}

#[test]
fn 格子点の上では標本そのものを返す() {
    let 高さ場 = 検査用の高さ場を作る();
    let 高さ = 高さ場.大域の水平位置から地表高さを求める(水平位置(12.0, -20.0)).unwrap();
    assert_eq!(高さ, 大域メートル::生成する(2.0));
    let 最遠の隅 = 高さ場.大域の水平位置から地表高さを求める(水平位置(14.0, -18.0)).unwrap();
    assert_eq!(最遠の隅, 大域メートル::生成する(7.0));
}

/// 検査用の高さ場は四隅が同一平面に乗るため、升目の中央の値は四隅の平均に一致する。
#[test]
fn 同一平面の升目の中央では四隅の平均を返す() {
    let 高さ場 = 検査用の高さ場を作る();
    let 高さ = 高さ場.大域の水平位置から地表高さを求める(水平位置(11.0, -19.0)).unwrap();
    assert_eq!(高さ, 大域メートル::生成する(3.5));
}

#[test]
fn 広がりの外の問い合わせを型付きエラーにする() {
    let 高さ場 = 検査用の高さ場を作る();
    assert!(高さ場.大域の水平位置から地表高さを求める(水平位置(9.999, -20.0)).is_err());
    assert!(高さ場.大域の水平位置から地表高さを求める(水平位置(14.001, -20.0)).is_err());
    assert!(高さ場.大域の水平位置から地表高さを求める(水平位置(12.0, -17.999)).is_err());
}

#[test]
fn 読み口は高さ場の有無と広がりの外を枝で答える() {
    let 持たない世界 = 高さ場の読み口::高さ場を持たない世界;
    assert_eq!(
        持たない世界.大域の水平位置から地表高さを求める(水平位置(12.0, -20.0)),
        地表高さの問い合わせ結果::高さ場を持たない世界
    );
    let 持つ世界 = 高さ場の読み口::高さ場を持つ世界(検査用の高さ場を作る());
    assert_eq!(
        持つ世界.大域の水平位置から地表高さを求める(水平位置(12.0, -20.0)),
        地表高さの問い合わせ結果::地表高さ(大域メートル::生成する(2.0))
    );
    assert_eq!(
        持つ世界.大域の水平位置から地表高さを求める(水平位置(100.0, -20.0)),
        地表高さの問い合わせ結果::高さ場の広がりの外
    );
}

#[test]
fn 読み口は高さ場の水平な広がりの中心を返す() {
    let 持たない世界 = 高さ場の読み口::高さ場を持たない世界;
    assert_eq!(持たない世界.世界の中心の水平位置(), None);
    let 持つ世界 = 高さ場の読み口::高さ場を持つ世界(検査用の高さ場を作る());
    assert_eq!(持つ世界.世界の中心の水平位置(), Some(水平位置(12.0, -19.0)));
}
