//! 高さ場の1点で、描画が実際に張る三角形の平面を読む問い合わせ。受け取るのは大域の水平位置、返すのは
//! 地表の大域位置と上向きの単位法線と2方向の単位接線、およびどの升目のどちらの三角形かである。
//! 触れるのは諸元と格子点の標本の読み出しだけであり、高さ場の生成も実行時形式の往復も持たない。
//!
//! 高さだけの問い合わせもこの工程を通す。三角形の選び方を2つ持つと、高さを求めた三角形と法線を求めた
//! 三角形が食い違い、面に乗っていない足元が生まれる。

use blitz_collision::height_field::{
    升目の一辺, 升目の中の比, 升目の値の生成エラー, 升目の四隅の高さ, 升目の地表の面, 地表の単位向き
};
use blitz_math::{ワールド, 大域メートル, 大域ワールド位置, 方向};

use super::cell_position::{升目の中の位置, 大域の水平位置を升目の中の位置へ写す};
use super::error::高さ場の広がりの外エラー;
use super::field::高さ場;
use super::ground_surface::世界の地表の面;
use super::triangle_location::地表の三角形の所在;

impl 高さ場 {
    /// 大域ワールド位置の水平2成分(東と南)から、その点の地表の面を求める。
    /// 高さ場の広がりの外を問い合わせた場合は型付きエラーにし、水平な面へ落とさない。
    pub fn 大域の水平位置から地表の面を求める(
        &self,
        位置: 大域ワールド位置,
    ) -> Result<世界の地表の面, 高さ場の広がりの外エラー> {
        let 升目 = 大域の水平位置を升目の中の位置へ写す(self.諸元(), 位置)?;
        let 面 = self.升目の中の地表の面を求める(升目);
        Ok(升目の面を世界の地表の面へ写す(
            大域ワールド位置::生成する(位置.x(), 大域メートル::生成する(面.高さ()), 位置.z()),
            面,
            地表の三角形の所在::生成する(升目.東添字, 升目.南添字, 面.三角形()),
        ))
    }

    fn 升目の中の地表の面を求める(&self, 升目: 升目の中の位置) -> 升目の地表の面<f64> {
        let 四隅 = 升目の値を取り出す(升目の四隅の高さ::生成する(
            self.升目の隅の高さ(升目.東添字, 升目.南添字),
            self.升目の隅の高さ(升目.東添字 + 1, 升目.南添字),
            self.升目の隅の高さ(升目.東添字, 升目.南添字 + 1),
            self.升目の隅の高さ(升目.東添字 + 1, 升目.南添字 + 1),
        ));
        let 比 = 升目の値を取り出す(升目の中の比::生成する(升目.東の比, 升目.南の比));
        let 一辺 = 升目の値を取り出す(升目の一辺::生成する(f64::from(self.諸元().格子間隔().値())));
        升目の値を取り出す(四隅.地表の面を求める(比, 一辺))
    }

    /// 標本をf64へ広げてから混ぜるのは、単精度の標本どうしの差が刻みより細かいときに計算の途中で失われないためである。
    ///
    /// 注意: 呼んでよいのは升目の中の位置を求めた後だけである。その工程が四隅すべての格子添字が格子に収まることを保証する。
    fn 升目の隅の高さ(&self, 東添字: u32, 南添字: u32) -> f64 {
        match self.格子点の高さ(東添字, 南添字) {
            Ok(高さ) => f64::from(高さ.値()),
            Err(誤り) => panic!("升目の四隅の格子添字が格子の外だった(不変条件の破れ): {誤り}"),
        }
    }
}

/// 升目1つの中で読んだ面を、世界の語彙の地表の面へ写す。地表の大域位置と所在は格子のどこかという呼び出し側の話であり、
/// 法線と接線は面の傾きだけから決まる。高さだけの問い合わせと線分の問い合わせがこの1つの写しを共有するのは、
/// 同じ面から2通りの法線が出ることを防ぐためである。
pub(super) fn 升目の面を世界の地表の面へ写す(
    地表の大域位置: 大域ワールド位置,
    面: 升目の地表の面<f64>,
    所在: 地表の三角形の所在,
) -> 世界の地表の面 {
    let 傾き = 面.傾き();
    世界の地表の面::生成する(
        地表の大域位置,
        単位向きを方向へ写す(傾き.上向きの単位法線()),
        単位向きを方向へ写す(傾き.東向きの単位接線()),
        単位向きを方向へ写す(傾き.南向きの単位接線()),
        所在,
    )
}

/// 高さ場の検証(標本が有限で絶対値が上限以下・格子間隔が正の有限値)と升目の中の位置の作り方から、
/// 衝突数学の値の検査は必ず通る。
/// 導いた面の検査も通る。単精度の標本どうしの差と正の格子間隔の商は、倍精度で扱う限り必ず有限に収まるためである。
/// 通らなければ高さ場の不変条件が破れているため、無言で代わりの値を返さず止める。
fn 升目の値を取り出す<値>(結果: Result<値, 升目の値の生成エラー>) -> 値 {
    match 結果 {
        Ok(値) => 値,
        Err(誤り) => panic!("高さ場が渡した升目の値を衝突数学が拒んだ(不変条件の破れ): {誤り}"),
    }
}

/// 地表の単位向きをワールド空間の単位方向へ写す。傾きは有限であり法線の天頂成分は正であるため、
/// 長さは必ず1になる。ならなければ上と同じ不変条件の破れである。
fn 単位向きを方向へ写す(向き: 地表の単位向き<f64>) -> 方向<ワールド> {
    match 向き.方向へ狭める() {
        Ok(方向) => 方向,
        Err(誤り) => panic!("地表の面の向きが単位方向にならなかった(不変条件の破れ): {誤り}"),
    }
}
