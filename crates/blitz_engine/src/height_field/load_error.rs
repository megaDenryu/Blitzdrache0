//! カタログ経由で高さ場アセットを読み込むときに返す型付きエラー。
//!
//! カタログに安定IDの登録が無いことはこの語彙に入らない。登録が無い世界は失敗ではなく「高さ場を持たない世界」であり、
//! `高さ場の読み口`の枝が表す。ここに集めるのは、登録があるのに読めなかった3つの破れ方である。

use crate::asset::{アセットIDエラー, 高さ場実行時形式エラー};

#[derive(Debug, thiserror::Error)]
pub enum 高さ場読込エラー {
    #[error("高さ場の安定IDを組み立てられない: {0}")]
    安定IDが不正(#[from] アセットIDエラー),
    #[error("高さ場アセットのファイル読込に失敗した: {0}")]
    ファイル読込失敗(String),
    #[error("高さ場アセットの形式検査に失敗した: {0}")]
    形式不正(#[from] 高さ場実行時形式エラー),
}
