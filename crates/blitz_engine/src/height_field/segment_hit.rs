//! 線分が高さ場の地表に最初に当たった点を、世界の語彙で表した値と、当たらなかったことを表す枝。
//!
//! 交差位置を別に持たないのは、地表の面が持つ地表の大域位置がその点そのものだからである。
//! 当たった点では線分の上の点と地表の上の点が一致するため、2つ持つと同じ事実の写しが2つできる。

use blitz_collision::height_field::線分の媒介変数;

use super::ground_surface::世界の地表の面;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 線分が最初に当たる地表 {
    地表に当たらない,
    地表に当たる(線分と地表の当たり),
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 線分と地表の当たり {
    交差時刻: 線分の媒介変数,
    地表の面: 世界の地表の面,
}

impl 線分と地表の当たり {
    pub fn 生成する(交差時刻: 線分の媒介変数, 地表の面: 世界の地表の面) -> Self {
        Self { 交差時刻, 地表の面 }
    }

    /// 線分の始点を0、終点を1として測った、最初に地表へ達した時刻。始点が既に地表より下にある線分では0になる。
    pub fn 交差時刻(&self) -> 線分の媒介変数 {
        self.交差時刻
    }

    /// 当たった点の地表の面。地表の大域位置がそのまま交差位置であり、上向きの単位法線・2方向の単位接線・
    /// どの升目のどちらの三角形かを併せて持つ。
    pub fn 地表の面(&self) -> 世界の地表の面 {
        self.地表の面
    }
}
