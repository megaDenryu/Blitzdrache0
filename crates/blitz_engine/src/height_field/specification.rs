//! 高さ場の諸元。格子原点の大域の水平位置・格子間隔・方向ごとの格子点数を持ち、標本数と格子の広がりを導出する。
//! 値の検証をこの型へ集めるため、高さ場の実体は標本数が諸元と合うことだけを確かめればよい。

use blitz_math::{メートル, 大域メートル};

use super::error::高さ場エラー;

/// 1方向の格子点数の上限。この値なら東西と南北の積が32ビット整数へ必ず収まるため、標本数の桁あふれを型の範囲だけで排除できる。
/// 一辺65535点は刻み1メートルでも65キロメートル四方にあたり、8キロメートル四方級の世界を上回る。
const 格子点数上限: u32 = 65_535;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 高さ場諸元 {
    格子原点の東成分: 大域メートル,
    格子原点の南成分: 大域メートル,
    格子間隔: メートル,
    東方向の格子点数: u32,
    南方向の格子点数: u32,
}

impl 高さ場諸元 {
    pub fn 生成する(
        格子原点の東成分: 大域メートル,
        格子原点の南成分: 大域メートル,
        格子間隔: メートル,
        東方向の格子点数: u32,
        南方向の格子点数: u32,
    ) -> Result<Self, 高さ場エラー> {
        if !格子原点の東成分.値().is_finite() || !格子原点の南成分.値().is_finite() {
            return Err(高さ場エラー::格子原点が有限でない);
        }
        if !格子間隔.値().is_finite() || 格子間隔.値() <= 0.0 {
            return Err(高さ場エラー::格子間隔が正の有限値でない);
        }
        // 区分線形の面は升目の四隅を読むため、どちらの方向にも升目が1つ以上要る。
        if 東方向の格子点数 < 2 || 南方向の格子点数 < 2 {
            return Err(高さ場エラー::格子点数不足 {
                東方向: 東方向の格子点数,
                南方向: 南方向の格子点数,
            });
        }
        if 東方向の格子点数 > 格子点数上限 || 南方向の格子点数 > 格子点数上限 {
            return Err(高さ場エラー::格子点数過大 {
                東方向: 東方向の格子点数,
                南方向: 南方向の格子点数,
                上限: 格子点数上限,
            });
        }
        Ok(Self {
            格子原点の東成分,
            格子原点の南成分,
            格子間隔,
            東方向の格子点数,
            南方向の格子点数,
        })
    }

    pub fn 格子原点の東成分(&self) -> 大域メートル {
        self.格子原点の東成分
    }

    pub fn 格子原点の南成分(&self) -> 大域メートル {
        self.格子原点の南成分
    }

    pub fn 格子間隔(&self) -> メートル {
        self.格子間隔
    }

    pub fn 東方向の格子点数(&self) -> u32 {
        self.東方向の格子点数
    }

    pub fn 南方向の格子点数(&self) -> u32 {
        self.南方向の格子点数
    }

    /// 保持する標本の総数。生成の上限検査により、この積は32ビット整数へ必ず収まる。
    pub fn 標本数(&self) -> u32 {
        self.東方向の格子点数 * self.南方向の格子点数
    }

    pub(super) fn 標本数をusizeへ変換する(&self) -> Result<usize, 高さ場エラー> {
        usize::try_from(self.標本数()).map_err(|_| 高さ場エラー::標本数表現不能(self.標本数()))
    }
}
