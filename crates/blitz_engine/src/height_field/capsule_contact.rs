//! 掃引したカプセルが地表に最初に触れた点を、世界の語彙で表した値と、触れなかったことを表す枝。
//!
//! 地表の面(高さ・接線)を持たないのは、触れた先が面とは限らないためである。辺と頂点に触れたときは
//! その点に接する平面が定まらず、接線も定まらない。答えとして意味を持つのは、接触の位置と、
//! 接触位置からカプセルの軸へ向かう単位法線と、どの升目のどちらの三角形のどの特徴かの3つである。

use blitz_collision::height_field::{地表に触れた特徴, 掃引で動けた割合};
use blitz_math::{ワールド, 大域ワールド位置, 方向};

use super::triangle_location::地表の三角形の所在;

/// 掃引したカプセルが地表に最初に触れた点を世界の語彙で表したもの。変位の全体を動いても触れなかった枝と、
/// 触れた接触を持つ枝の2つである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 掃引したカプセルが最初に触れる地表 {
    地表に触れない,
    地表に触れる(カプセルと地表の接触),
}

/// 掃引したカプセルが地表へ触れた1つの事実。動けた割合・接触の大域位置・接触の単位法線・触れた三角形の所在・
/// 触れた特徴を持つ。地表の面(高さ・接線)を持たないのは、辺と頂点に触れたときにその点で接する平面が
/// 定まらないためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct カプセルと地表の接触 {
    動けた割合: 掃引で動けた割合,
    接触の大域位置: 大域ワールド位置,
    接触の単位法線: 方向<ワールド>,
    所在: 地表の三角形の所在,
    触れた特徴: 地表に触れた特徴,
}

impl カプセルと地表の接触 {
    pub fn 生成する(
        動けた割合: 掃引で動けた割合,
        接触の大域位置: 大域ワールド位置,
        接触の単位法線: 方向<ワールド>,
        所在: 地表の三角形の所在,
        触れた特徴: 地表に触れた特徴,
    ) -> Self {
        Self {
            動けた割合,
            接触の大域位置,
            接触の単位法線,
            所在,
            触れた特徴,
        }
    }

    /// 掃引の変位のうち、地表に触れるまでに動けた分の割合。動く前から触れていた場合は0である。
    pub fn 動けた割合(&self) -> 掃引で動けた割合 {
        self.動けた割合
    }

    pub fn 接触の大域位置(&self) -> 大域ワールド位置 {
        self.接触の大域位置
    }

    /// 接触位置からカプセルの軸へ向かう単位方向。面に触れたときはその三角形の上向きの単位法線と同じである。
    pub fn 接触の単位法線(&self) -> 方向<ワールド> {
        self.接触の単位法線
    }

    /// 触れた三角形が、どの升目のどちらの三角形か。
    pub fn 所在(&self) -> 地表の三角形の所在 {
        self.所在
    }

    /// その三角形の面・辺・頂点のどれに触れたか。
    pub fn 触れた特徴(&self) -> 地表に触れた特徴 {
        self.触れた特徴
    }
}
