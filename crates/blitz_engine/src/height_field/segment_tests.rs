//! 高さ場の線分の問い合わせの反証。大域の位置と格子原点からの位置の写し合わせが正しいこと、当たった点で
//! 地表の面と所在が返ること、高さ場の広がりの外へ出た問い合わせが完全性で伝わること、読み口が枝で答えることを見る。
//!
//! 期待値は検査用の高さ場の平面から手で解く。この高さ場は格子原点が東10メートル・南-20メートル、
//! 格子間隔が2メートルであり、東へ1メートルで0.5メートル、南へ1メートルで2メートル上がる1枚の平面である。
//! したがって東12メートル・南-20メートルの地表高さは2メートル、東11メートル・南-19メートルの地表高さは3.5メートルである。

#![allow(clippy::unwrap_used)]

use blitz_math::{大域メートル, 大域ワールド位置};

use super::height_field_tests::検査用の高さ場を作る;
use super::{
    升目の三角形, 線分が最初に当たる地表, 線分が最初に当たる地表の問い合わせ結果, 高さ場の読み口
};
use crate::問い合わせ完全性;

fn 大域位置(東: f64, 天頂: f64, 南: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(東), 大域メートル::生成する(天頂), 大域メートル::生成する(南))
}

fn 当たりを取り出す(結果: 線分が最初に当たる地表) -> super::線分と地表の当たり {
    let 線分が最初に当たる地表::地表に当たる(当たり) = 結果 else {
        panic!("線分が地表に当たらなかった");
    };
    当たり
}

/// 東11メートル・南-19メートルの真上から真下へ落ちる線分は、地表高さ3.5メートルで止まる。
/// 高さ5.5メートルから1.5メートルへ4メートル落ちる間に2メートルぶん降りた時点であるから、交差時刻は0.5である。
#[test]
fn 真下へ落ちる線分は地表の面と交差時刻を返す() {
    let 答え = 検査用の高さ場を作る()
        .線分が最初に当たる地表を求める(大域位置(11.0, 5.5, -19.0), 大域位置(11.0, 1.5, -19.0))
        .unwrap();
    assert_eq!(答え.完全性(), 問い合わせ完全性::対象範囲を完全に評価できた);
    let 当たり = 当たりを取り出す(*答え.値());
    assert_eq!(当たり.交差時刻().値(), 0.5);
    assert_eq!(当たり.地表の面().地表の大域位置(), 大域位置(11.0, 3.5, -19.0));
    assert_eq!(当たり.地表の面().所在().升目の東添字(), 0);
    assert_eq!(当たり.地表の面().所在().升目の南添字(), 0);
    assert_eq!(当たり.地表の面().所在().三角形(), 升目の三角形::奥側);
}

/// 地表より高いところを水平に通る線分は当たらない。格子の中に収まっているため完全性は完全である。
#[test]
fn 地表の上を水平に通る線分は当たらないまま全体を調べる() {
    let 答え = 検査用の高さ場を作る()
        .線分が最初に当たる地表を求める(大域位置(11.0, 20.0, -19.0), 大域位置(13.0, 20.0, -19.0))
        .unwrap();
    assert_eq!(答え.完全性(), 問い合わせ完全性::対象範囲を完全に評価できた);
    assert_eq!(*答え.値(), 線分が最初に当たる地表::地表に当たらない);
}

/// 格子の広がりの外へ出る線分は、外へ出た升目で走査を打ち切り、完全性が評価できない領域を含むになる。
#[test]
fn 広がりの外へ出る線分は完全性で伝える() {
    let 答え = 検査用の高さ場を作る()
        .線分が最初に当たる地表を求める(大域位置(11.0, 20.0, -19.0), 大域位置(40.0, 20.0, -19.0))
        .unwrap();
    assert_eq!(答え.完全性(), 問い合わせ完全性::評価できない領域を含む);
    assert_eq!(*答え.値(), 線分が最初に当たる地表::地表に当たらない);
}

/// 始点が既に地表より下にある線分は交差時刻0で当たる。地面の中から見上げる視点を遮られていないと答えないためである。
#[test]
fn 始点が地表の下にある線分は交差時刻0で当たる() {
    let 答え = 検査用の高さ場を作る()
        .線分が最初に当たる地表を求める(大域位置(11.0, 0.0, -19.0), 大域位置(11.0, 10.0, -19.0))
        .unwrap();
    let 当たり = 当たりを取り出す(*答え.値());
    assert_eq!(当たり.交差時刻().値(), 0.0);
}

#[test]
fn 読み口は高さ場を持たない世界を枝で答える() {
    let 持たない世界 = 高さ場の読み口::高さ場を持たない世界;
    assert_eq!(
        持たない世界.線分が最初に当たる地表を求める(大域位置(11.0, 5.5, -19.0), 大域位置(11.0, 1.5, -19.0)),
        線分が最初に当たる地表の問い合わせ結果::高さ場を持たない世界
    );
    let 持つ世界 = 高さ場の読み口::高さ場を持つ世界(検査用の高さ場を作る());
    let 線分が最初に当たる地表の問い合わせ結果::線分を評価した結果(答え) =
        持つ世界.線分が最初に当たる地表を求める(大域位置(11.0, 5.5, -19.0), 大域位置(11.0, 1.5, -19.0))
    else {
        panic!("高さ場を持つ世界が線分を評価しなかった");
    };
    assert_eq!(当たりを取り出す(*答え.値()).交差時刻().値(), 0.5);
}

/// 端点に有限でない値が渡った線分は、当たらなかったことと混ぜずに型付きエラーの枝で答える。
#[test]
fn 端点が有限でない線分は評価できない枝で答える() {
    let 持つ世界 = 高さ場の読み口::高さ場を持つ世界(検査用の高さ場を作る());
    let 結果 = 持つ世界.線分が最初に当たる地表を求める(大域位置(11.0, f64::NAN, -19.0), 大域位置(11.0, 1.5, -19.0));
    assert!(matches!(結果, 線分が最初に当たる地表の問い合わせ結果::線分を評価できない(_)));
}
