//! 高さ場を、衝突数学の走査へ升目の四隅の高さを答える供給元として見せる実装。
//! 触れるのは諸元と標本の読み出しだけであり、面の計算も線分の走査も持たない。
//!
//! 四隅のどれか1つでも格子の広がりの外にあれば答えを返さない。走査はそこで打ち切り、
//! 呼び出し側は問い合わせの完全性として受け取る。無言で縁の高さを引き伸ばすと、
//! 高さ場の外に存在しない地面が生まれる。

use blitz_collision::height_field::{升目の四隅の高さ, 升目の四隅の高さの供給元, 升目の格子添字};

use super::field::高さ場;

impl 升目の四隅の高さの供給元 for 高さ場 {
    fn 升目の四隅の高さを参照する(&self, 添字: 升目の格子添字) -> Option<升目の四隅の高さ<f64>> {
        let 東の次 = 添字.東添字().checked_add(1)?;
        let 南の次 = 添字.南添字().checked_add(1)?;
        升目の四隅の高さ::生成する(
            self.格子点の高さを倍精度で読む(添字.東添字(), 添字.南添字())?,
            self.格子点の高さを倍精度で読む(東の次, 添字.南添字())?,
            self.格子点の高さを倍精度で読む(添字.東添字(), 南の次)?,
            self.格子点の高さを倍精度で読む(東の次, 南の次)?,
        )
        .ok()
    }
}

impl 高さ場 {
    /// 符号付きの格子添字で標本を読み、格子の広がりの外なら`None`を返す。
    /// 標本をf64へ広げるのは、単精度の標本どうしの差が刻みより細かいときに計算の途中で失われないためである。
    fn 格子点の高さを倍精度で読む(&self, 東添字: i32, 南添字: i32) -> Option<f64> {
        let 東添字 = u32::try_from(東添字).ok()?;
        let 南添字 = u32::try_from(南添字).ok()?;
        self.格子点の高さ(東添字, 南添字).ok().map(|高さ| f64::from(高さ.値()))
    }
}
