//! 大域ワールド位置と、高さ場の格子原点を基準にした位置の写し合わせ。触れるのは諸元の格子原点だけである。
//!
//! この写しを世界の側が持つのは、衝突数学層が世界の原点も世界の広がりも知らないためである。
//! 天頂の成分は写さずそのまま運ぶ。高さの標本の基準と大域ワールド位置の縦の基準が同じであり、
//! 格子原点は水平の2成分しか持たないからである。

use blitz_collision::height_field::{高さ場の位置の生成エラー, 高さ場の格子原点からの位置};
use blitz_math::{大域メートル, 大域ワールド位置};

use super::field::高さ場;

impl 高さ場 {
    pub(super) fn 大域位置を格子原点からの位置へ写す(
        &self,
        位置: 大域ワールド位置,
    ) -> Result<高さ場の格子原点からの位置, 高さ場の位置の生成エラー> {
        高さ場の格子原点からの位置::生成する(
            位置.x().値() - self.諸元().格子原点の東成分().値(),
            位置.y().値(),
            位置.z().値() - self.諸元().格子原点の南成分().値(),
        )
    }

    pub(super) fn 格子原点からの位置を大域位置へ写す(
        &self, 位置: 高さ場の格子原点からの位置
    ) -> 大域ワールド位置 {
        大域ワールド位置::生成する(
            大域メートル::生成する(位置.東のメートル() + self.諸元().格子原点の東成分().値()),
            大域メートル::生成する(位置.天頂のメートル()),
            大域メートル::生成する(位置.南のメートル() + self.諸元().格子原点の南成分().値()),
        )
    }
}
