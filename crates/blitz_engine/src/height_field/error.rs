//! 高さ場の諸元の検証・標本の並び・格子添字の範囲の失敗を、この1つの語彙で表す。
//!
//! 注意: この型はアセット実行時形式エラーへ`#[from]`で畳み込むため、`Copy`と`Eq`を保つ必要がある。
//! そのため有限でない小数や範囲外の格子間隔を値として持たず、破れた条件の名前だけを持つ。
//! 問い合わせ位置の範囲外は実行時形式の失敗ではないため、この語彙でなく`高さ場の広がりの外エラー`が表す。

use thiserror::Error;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Error)]
pub enum 高さ場エラー {
    #[error("高さ場の格子原点が有限な大域メートルでない")]
    格子原点が有限でない,
    #[error("高さ場の格子間隔が正の有限値でない")]
    格子間隔が正の有限値でない,
    #[error("高さ場の格子点数は各方向2以上でなければならない: 東方向{東方向}、南方向{南方向}")]
    格子点数不足 { 東方向: u32, 南方向: u32 },
    #[error("高さ場の格子点数が上限{上限}を超えている: 東方向{東方向}、南方向{南方向}")]
    格子点数過大 { 東方向: u32, 南方向: u32, 上限: u32 },
    #[error("高さ場の標本数が諸元と合わない: 期待{期待}、実際{実際}")]
    標本数不一致 { 期待: usize, 実際: usize },
    #[error("高さ場の標本数をこの処理系のusizeで表せない: {0}")]
    標本数表現不能(u32),
    #[error("高さ場に有限でない高さが含まれる")]
    高さが有限でない,
    #[error("高さ場の格子添字が有効範囲の外である: 東{東添字}、南{南添字}")]
    格子添字範囲外 { 東添字: u32, 南添字: u32 },
}

/// 問い合わせた水平位置が高さ場の広がりの外だったことを表す失敗。位置を値として持つため`Eq`を持たず、
/// アセット実行時形式エラーへは畳み込まない。焼かれた高さ場を読む工程では起きず、実行中の問い合わせだけで起きる。
#[derive(Debug, Clone, Copy, PartialEq, Error)]
#[error("問い合わせ位置が高さ場の広がりの外である: 東{東の大域メートル}、南{南の大域メートル}")]
pub struct 高さ場の広がりの外エラー {
    pub 東の大域メートル: f64,
    pub 南の大域メートル: f64,
}
