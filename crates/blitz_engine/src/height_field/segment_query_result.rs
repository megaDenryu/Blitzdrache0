//! 線分が最初に当たる地表の問い合わせに対する答え。高さだけの問い合わせと同じく、高さ場を持たない世界を
//! 別の枝で表す。
//!
//! 高さ場の広がりの外を枝にしないのは、線分が途中まで調べられることがあるためである。1点の問い合わせと違い、
//! 「線分の全体が外」と「途中から外」は別の事実であり、1つの枝では区別できない。区別は答えに付く
//! 問い合わせ完全性が担う。
//! 線分そのものを評価できない場合を枝で持つのは、端点に有限でない値が渡ったことが呼び出し側の誤りであり、
//! 当たらなかったことと混ぜてはならないためである。

use blitz_collision::height_field::線分の問い合わせエラー;

use super::segment_hit::線分が最初に当たる地表;
use crate::world_query::世界問い合わせ結果;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 線分が最初に当たる地表の問い合わせ結果 {
    高さ場を持たない世界,                                           // 高さ場アセットをカタログに持たない
    線分を評価できない(線分の問い合わせエラー),                     // 端点が有限でない等、線分の側が壊れている
    線分を評価した結果(世界問い合わせ結果<線分が最初に当たる地表>), // 当たりの有無と問い合わせ完全性
}
