//! 区分線形の地表の面の反証。四隅が同一平面に乗らない鞍型の升目で双一次でなく三角形の面の高さを返すこと、
//! 面が所在と法線を返すこと、対角の両側で三角形が切り替わること、接線が面の傾きを表すこと、
//! 読み口が3つの枝で答えることを見る。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};

use super::height_field_tests::{検査用の高さ場を作る, 水平位置};
use super::{升目の三角形, 地表の面の問い合わせ結果, 高さ場, 高さ場の読み口, 高さ場諸元};

/// 四隅が同一平面に乗らない鞍型の高さ場。格子原点は東0・南0、格子間隔は1メートル、
/// 高さは手前左0・手前右1・奥左1・奥右0である。
fn 鞍型の高さ場を作る() -> 高さ場 {
    let 諸元 = 高さ場諸元::生成する(大域メートル::生成する(0.0), 大域メートル::生成する(0.0), メートル::生成する(1.0), 2, 2).unwrap();
    高さ場::生成する(諸元, [0.0, 1.0, 1.0, 0.0].map(メートル::生成する).to_vec()).unwrap()
}

/// 同じ2点を双一次で混ぜるとどちらも0.625になり、描画が張る三角形の面から0.125メートル外れる。
#[test]
fn 鞍型の升目では双一次でなく三角形の面の高さを返す() {
    let 高さ場 = 鞍型の高さ場を作る();
    assert_eq!(
        高さ場.大域の水平位置から地表高さを求める(水平位置(0.25, 0.75)).unwrap(),
        大域メートル::生成する(0.5)
    );
    assert_eq!(
        高さ場.大域の水平位置から地表高さを求める(水平位置(0.75, 0.25)).unwrap(),
        大域メートル::生成する(0.5)
    );
}

#[test]
fn 鞍型の升目の面は地表の位置と所在と法線を返す() {
    let 面 = 鞍型の高さ場を作る().大域の水平位置から地表の面を求める(水平位置(0.25, 0.75)).unwrap();
    let 期待する位置 =
        大域ワールド位置::生成する(大域メートル::生成する(0.25), 大域メートル::生成する(0.5), 大域メートル::生成する(0.75));
    assert_eq!(面.地表の大域位置(), 期待する位置);
    assert_eq!(面.所在().升目の東添字(), 0);
    assert_eq!(面.所在().升目の南添字(), 0);
    assert_eq!(面.所在().三角形(), 升目の三角形::奥側);
    // 奥側の三角形の傾きは東へ-1・南へ1であり、正す前の法線は(1, 1, -1)である。
    let 三分の一の平方根 = (1.0_f32 / 3.0).sqrt();
    let 法線 = 面.上向きの単位法線();
    assert!((法線.x() - 三分の一の平方根).abs() < 1.0e-6, "法線の東成分が違う: {}", 法線.x());
    assert!((法線.y() - 三分の一の平方根).abs() < 1.0e-6, "法線の天頂成分が違う: {}", 法線.y());
    assert!((法線.z() + 三分の一の平方根).abs() < 1.0e-6, "法線の南成分が違う: {}", 法線.z());
}

#[test]
fn 対角の手前側では所在の三角形が切り替わる() {
    let 面 = 鞍型の高さ場を作る().大域の水平位置から地表の面を求める(水平位置(0.75, 0.25)).unwrap();
    assert_eq!(面.所在().三角形(), 升目の三角形::手前側);
}

/// 検査用の高さ場は東へ1メートルで0.5メートル、南へ1メートルで2メートル上がる1枚の平面である。
/// 接線は長さ1に正されているため、勾配は天頂成分と水平成分の比で読む。
#[test]
fn 同一平面の升目では接線が面の傾きを表す() {
    let 面 = 検査用の高さ場を作る().大域の水平位置から地表の面を求める(水平位置(11.0, -19.0)).unwrap();
    assert_eq!(面.地表の大域位置().y(), 大域メートル::生成する(3.5));
    let 東の接線 = 面.東向きの単位接線();
    assert!((東の接線.y() / 東の接線.x() - 0.5).abs() < 1.0e-6, "東の接線の勾配が0.5でない");
    let 南の接線 = 面.南向きの単位接線();
    assert!((南の接線.y() / 南の接線.z() - 2.0).abs() < 1.0e-6, "南の接線の勾配が2でない");
}

#[test]
fn 読み口は地表の面も3つの枝で答える() {
    let 持たない世界 = 高さ場の読み口::高さ場を持たない世界;
    assert_eq!(
        持たない世界.大域の水平位置から地表の面を求める(水平位置(0.25, 0.75)),
        地表の面の問い合わせ結果::高さ場を持たない世界
    );
    let 持つ世界 = 高さ場の読み口::高さ場を持つ世界(鞍型の高さ場を作る());
    assert_eq!(
        持つ世界.大域の水平位置から地表の面を求める(水平位置(100.0, 0.0)),
        地表の面の問い合わせ結果::高さ場の広がりの外
    );
    let 地表の面の問い合わせ結果::地表の面(面) = 持つ世界.大域の水平位置から地表の面を求める(水平位置(0.25, 0.75))
    else {
        panic!("高さ場の中の問い合わせが地表の面を返さなかった");
    };
    assert_eq!(面.所在().三角形(), 升目の三角形::奥側);
}
