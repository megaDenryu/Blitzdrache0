//! 高さ場の実体。諸元と、南が外側・東が内側の昇順で並べた高さの列を保持し、大域の水平位置での地表高さに答える。
//! 並びを高さ格子と同じ走査順にするのは、格子を貼り合わせて焼く工程が並べ替えを1度も行わずに済むためである。

use blitz_math::{メートル, 大域メートル, 大域ワールド位置};

use super::error::{高さ場の広がりの外エラー, 高さ場エラー};
use super::specification::高さ場諸元;

#[derive(Debug, Clone, PartialEq)]
pub struct 高さ場 {
    諸元: 高さ場諸元,
    高さ一覧: Vec<メートル>,
}

impl 高さ場 {
    pub fn 生成する(諸元: 高さ場諸元, 高さ一覧: Vec<メートル>) -> Result<Self, 高さ場エラー> {
        let 期待 = 諸元.標本数をusizeへ変換する()?;
        if 高さ一覧.len() != 期待 {
            return Err(高さ場エラー::標本数不一致 {
                期待, 実際: 高さ一覧.len()
            });
        }
        if 高さ一覧.iter().any(|高さ| !高さ.値().is_finite()) {
            return Err(高さ場エラー::高さが有限でない);
        }
        Ok(Self { 諸元, 高さ一覧 })
    }

    pub fn 諸元(&self) -> 高さ場諸元 {
        self.諸元
    }

    pub fn 高さ一覧(&self) -> &[メートル] {
        &self.高さ一覧
    }

    /// 格子添字で標本そのものを参照する。範囲外は型付きエラーにする。
    pub fn 格子点の高さ(&self, 東添字: u32, 南添字: u32) -> Result<メートル, 高さ場エラー> {
        let 範囲外 = 高さ場エラー::格子添字範囲外 { 東添字, 南添字 };
        if 東添字 >= self.諸元.東方向の格子点数() || 南添字 >= self.諸元.南方向の格子点数() {
            return Err(範囲外);
        }
        let 位置 = 南添字
            .checked_mul(self.諸元.東方向の格子点数())
            .and_then(|行の先頭| 行の先頭.checked_add(東添字))
            .ok_or(範囲外)?;
        let 位置 = usize::try_from(位置).map_err(|_| 範囲外)?;
        self.高さ一覧.get(位置).copied().ok_or(範囲外)
    }

    /// 大域ワールド位置の水平2成分(東と南)から地表高さを求める。格子点の間は、描画が実際に張る2つの三角形の
    /// 平面をそのまま使う区分線形である。高さ場の広がりの外を問い合わせた場合は型付きエラーにし、0メートルへ落とさない。
    ///
    /// 地表の面の問い合わせと同じ工程を通すのは、高さを求めた三角形と法線を求めた三角形を食い違わせないためである。
    /// 参照: `crates/blitz_engine/src/height_field/field_ground_surface.rs`
    pub fn 大域の水平位置から地表高さを求める(
        &self,
        位置: 大域ワールド位置,
    ) -> Result<大域メートル, 高さ場の広がりの外エラー> {
        Ok(self.大域の水平位置から地表の面を求める(位置)?.地表の大域位置().y())
    }
}
