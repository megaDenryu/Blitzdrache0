//! 地表の面の問い合わせに対する答え。高さだけの問い合わせと同じ3枝の様式であり、高さ場を持たない世界と
//! 高さ場の広がりの外を別々の枝で表す。
//!
//! 枝で表すのは、どちらの場合も「面が分からない」ことを呼び出し側が知る必要があり、水平な面を返すと
//! 本当に水平な地表と区別できなくなるためである。

use super::ground_surface::世界の地表の面;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 地表の面の問い合わせ結果 {
    高さ場を持たない世界,     // 高さ場アセットをカタログに持たない
    高さ場の広がりの外,       // 高さ場は持つが問い合わせた水平位置が広がりの外
    地表の面(世界の地表の面), // 高さ場から求めた地表の面
}
