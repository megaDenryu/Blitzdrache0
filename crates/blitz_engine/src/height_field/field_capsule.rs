//! 高さ場の上でカプセルを掃引し、地表に最初に触れるまでを求める問い合わせ。受け取るのは軸の両端の大域ワールド
//! 位置と半径と掃引の変位、返すのは動けた割合と接触の位置と法線と所在、および覆いのどこまでを調べられたかを
//! 表す完全性である。
//!
//! 覆いの升目を辿る走査も特徴ごとの求解も衝突数学層が持ち、この工程が担うのは語彙の写しだけである。
//! 大域の位置を格子原点からの位置へ写し、衝突数学へ自分自身を四隅の高さの供給元として渡し、
//! 返ってきた接触を世界の語彙へ写す。
//!
//! 掃引の変位を単精度の変位で受け取るのは、1刻みの移動量が呼び出し側では単精度で決まるためである。
//! 倍精度へ広げてから衝突数学へ渡すため、この写しで値は動かない。

use blitz_collision::height_field::{
    カプセルが地表に最初に触れる点, カプセルの掃引と高さ場の接触の結果, カプセルの掃引の問い合わせエラー, 升目の一辺, 掃引の走査が調べた範囲,
    高さ場のカプセルの掃引の問い合わせ, 高さ場の中の変位, 高さ場を掃引するカプセル,
};
use blitz_math::{メートル, ワールド, 変位, 大域ワールド位置};

use super::capsule_contact::{カプセルと地表の接触, 掃引したカプセルが最初に触れる地表};
use super::field::高さ場;
use super::field_ground_surface::単位向きを方向へ写す;
use super::field_segment::升目の添字を所在へ写す;
use crate::world_query::{世界問い合わせ結果, 問い合わせ完全性};

impl 高さ場 {
    /// 掃引したカプセルが地表に最初に触れるまでを求める。動く前から触れていたカプセルは動けた割合0で返す。
    /// 覆いの中に高さ場の広がりの外の升目があれば、そこにもっと早い接触がありうるため接触を答えず、
    /// 完全性が「評価できない領域を含む」になる。
    pub fn 掃引したカプセルが最初に触れる地表を求める(
        &self,
        軸の始点: 大域ワールド位置,
        軸の終点: 大域ワールド位置,
        半径: メートル,
        掃引の変位: 変位<ワールド>,
    ) -> Result<世界問い合わせ結果<掃引したカプセルが最初に触れる地表>, カプセルの掃引の問い合わせエラー> {
        let カプセル = 高さ場を掃引するカプセル::生成する(
            self.大域位置を格子原点からの位置へ写す(軸の始点)?,
            self.大域位置を格子原点からの位置へ写す(軸の終点)?,
            f64::from(半径.値()),
            高さ場の中の変位::生成する(
                f64::from(掃引の変位.x().値()),
                f64::from(掃引の変位.y().値()),
                f64::from(掃引の変位.z().値()),
            )?,
        )?;
        let 一辺 = 升目の一辺::生成する(f64::from(self.諸元().格子間隔().値()))?;
        let 結果 = 高さ場のカプセルの掃引の問い合わせ::生成する(self, 一辺).カプセルが地表に最初に触れる点を求める(&カプセル)?;
        Ok(self.接触と調べた範囲を世界の語彙へ写す(結果))
    }

    fn 接触と調べた範囲を世界の語彙へ写す(
        &self,
        結果: カプセルの掃引と高さ場の接触の結果,
    ) -> 世界問い合わせ結果<掃引したカプセルが最初に触れる地表> {
        let 完全性 = match 結果.調べた範囲() {
            掃引の走査が調べた範囲::覆いの升目をすべて調べた => {
                問い合わせ完全性::対象範囲を完全に評価できた
            }
            掃引の走査が調べた範囲::調べられない升目で打ち切った => {
                問い合わせ完全性::評価できない領域を含む
            }
        };
        let 触れる地表 = match 結果.最初に触れる点() {
            カプセルが地表に最初に触れる点::地表に触れない => {
                掃引したカプセルが最初に触れる地表::地表に触れない
            }
            カプセルが地表に最初に触れる点::地表に触れる(接触) => {
                掃引したカプセルが最初に触れる地表::地表に触れる(カプセルと地表の接触::生成する(
                    接触.動けた割合(),
                    self.格子原点からの位置を大域位置へ写す(接触.接触位置()),
                    単位向きを方向へ写す(接触.接触の単位法線()),
                    升目の添字を所在へ写す(接触.升目の添字(), 接触.三角形()),
                    接触.触れた特徴(),
                ))
            }
        };
        世界問い合わせ結果::生成する(触れる地表, 完全性)
    }
}
