//! 地表の三角形の所在: 問い合わせた点が高さ場のどの升目のどちらの三角形に乗っていたかである。
//! 面の値(位置・法線・接線)と別の型にするのは、所在が格子の話であって面の幾何ではなく、
//! 隣り合う問い合わせが同じ三角形に乗っているかを比べる用途がこの3つだけで足りるためである。

use blitz_collision::height_field::升目の三角形;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 地表の三角形の所在 {
    升目の東添字: u32,
    升目の南添字: u32,
    三角形: 升目の三角形,
}

impl 地表の三角形の所在 {
    pub fn 生成する(升目の東添字: u32, 升目の南添字: u32, 三角形: 升目の三角形) -> Self {
        Self {
            升目の東添字,
            升目の南添字,
            三角形,
        }
    }

    /// 升目の左手前の格子点の東添字。升目はこの添字と次の添字の間を占める。
    pub fn 升目の東添字(&self) -> u32 {
        self.升目の東添字
    }

    /// 升目の左手前の格子点の南添字。升目はこの添字と次の添字の間を占める。
    pub fn 升目の南添字(&self) -> u32 {
        self.升目の南添字
    }

    pub fn 三角形(&self) -> 升目の三角形 {
        self.三角形
    }
}
