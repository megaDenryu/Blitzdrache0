//! 掃引したカプセルが最初に触れる地表の問い合わせに対する答え。線分の問い合わせと同じ3枝の様式であり、
//! 高さ場を持たない世界と、掃引そのものを評価できない場合と、評価した結果を分ける。
//!
//! 高さ場の広がりの外を枝にしないのは、掃引の覆いが途中まで調べられることがあるためである。
//! 「覆いの全体が外」と「覆いの一部が外」は別の事実であり、1つの枝では区別できない。区別は答えに付く
//! 問い合わせ完全性が担う。
//! 掃引そのものを評価できない場合を枝で持つのは、半径が正の有限でないことや軸の位置が有限でないことが
//! 呼び出し側の誤りであり、触れなかったことと混ぜてはならないためである。

use blitz_collision::height_field::カプセルの掃引の問い合わせエラー;

use super::capsule_contact::掃引したカプセルが最初に触れる地表;
use crate::world_query::世界問い合わせ結果;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 掃引したカプセルが最初に触れる地表の問い合わせ結果 {
    高さ場を持たない世界,
    カプセルの掃引を評価できない(カプセルの掃引の問い合わせエラー),
    カプセルの掃引を評価した結果(世界問い合わせ結果<掃引したカプセルが最初に触れる地表>),
}
