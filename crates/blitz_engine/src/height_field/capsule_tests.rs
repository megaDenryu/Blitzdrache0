//! 高さ場のカプセルの掃引の反証。大域の位置と格子原点からの位置の写し合わせが正しいこと、接触の位置と法線と
//! 所在が返ること、覆いが高さ場の広がりの外へ出たことが完全性で伝わること、読み口が枝で答えることを見る。
//!
//! 検査用の高さ場は東へ1メートルで0.5メートル、南へ1メートルで2メートル上がる1枚の平面である。
//! この面の単位法線は東成分・天頂成分・南成分を1対マイナス2で割った向きであり、長さは5.25の平方根であるから、
//! 期待値は厳密な小数で書けない。そのため期待値を同じ解析の式で組み立て、差が10のマイナス12乗より
//! 小さいことを見る。式そのものは手で解いたものであり、実装とは別の道筋で書いてある。

#![allow(clippy::unwrap_used)]

use blitz_math::{メートル, ワールド, 位置, 変位, 大域メートル, 大域ワールド位置};

use super::height_field_tests::検査用の高さ場を作る;
use super::{
    カプセルと地表の接触, 升目の三角形, 地表に触れた特徴, 掃引したカプセルが最初に触れる地表, 掃引したカプセルが最初に触れる地表の問い合わせ結果,
    高さ場の読み口,
};
use crate::問い合わせ完全性;

/// 面の法線を正す前の長さ。東の傾きが0.5、南の傾きが2であるから、正す前の向きは東-0.5・天頂1・南-2である。
fn 法線の長さ() -> f64 {
    0.25f64.mul_add(1.0, 1.0 + 4.0).sqrt()
}

fn 大域位置(東: f64, 天頂: f64, 南: f64) -> 大域ワールド位置 {
    大域ワールド位置::生成する(大域メートル::生成する(東), 大域メートル::生成する(天頂), 大域メートル::生成する(南))
}

fn 変位(東: f32, 天頂: f32, 南: f32) -> 変位<ワールド> {
    位置::生成する(メートル::生成する(東), メートル::生成する(天頂), メートル::生成する(南)).原点からの変位()
}

fn 接触を取り出す(結果: 掃引したカプセルが最初に触れる地表) -> カプセルと地表の接触 {
    let 掃引したカプセルが最初に触れる地表::地表に触れる(接触) = 結果 else {
        panic!("カプセルが地表に触れなかった");
    };
    接触
}

/// 東11メートル・南-19メートルの真上から真下へ落ちるカプセル。その点の地表高さは3.5メートルであるから、
/// 下端の球の中心と面の隔たりは始まりで4.5を法線の長さで割った値である。真下へ4メートル進む掃引では
/// 隔たりが4を法線の長さで割った割合で縮むから、半径0.5メートルに達するのは4.5から0.5かける法線の長さを
/// 引いて4で割った時点である。
#[test]
fn 真下へ落ちるカプセルは面の特徴で触れる() {
    let 期待する割合 = 0.5f64.mul_add(-法線の長さ(), 4.5) / 4.0;
    let 答え = 検査用の高さ場を作る()
        .掃引したカプセルが最初に触れる地表を求める(
            大域位置(11.0, 8.0, -19.0),
            大域位置(11.0, 9.0, -19.0),
            メートル::生成する(0.5),
            変位(0.0, -4.0, 0.0),
        )
        .unwrap();
    assert_eq!(答え.完全性(), 問い合わせ完全性::対象範囲を完全に評価できた);
    let 接触 = 接触を取り出す(*答え.値());
    assert!((接触.動けた割合().値() - 期待する割合).abs() < 1.0e-12);
    let 接触点 = 接触.接触の大域位置();
    assert!((接触点.x().値() - (11.0 + 0.25 / 法線の長さ())).abs() < 1.0e-12);
    assert!((接触点.z().値() - (-19.0 + 1.0 / 法線の長さ())).abs() < 1.0e-12);
    assert!((f64::from(接触.接触の単位法線().y()) - 1.0 / 法線の長さ()).abs() < 1.0e-6);
    assert_eq!(接触.触れた特徴(), 地表に触れた特徴::三角形の面);
    assert_eq!(接触.所在().升目の東添字(), 0);
    assert_eq!(接触.所在().升目の南添字(), 0);
    assert_eq!(接触.所在().三角形(), 升目の三角形::奥側);
}

/// 覆いが高さ場の広がりの外へはみ出す掃引は、接触を答えずに完全性で伝える。半径3メートルのカプセルの覆いは
/// 格子の外まで広がる。
#[test]
fn 覆いが広がりの外へ出る掃引は完全性で伝える() {
    let 答え = 検査用の高さ場を作る()
        .掃引したカプセルが最初に触れる地表を求める(
            大域位置(11.0, 8.0, -19.0),
            大域位置(11.0, 9.0, -19.0),
            メートル::生成する(3.0),
            変位(0.0, -4.0, 0.0),
        )
        .unwrap();
    assert_eq!(答え.完全性(), 問い合わせ完全性::評価できない領域を含む);
    assert_eq!(*答え.値(), 掃引したカプセルが最初に触れる地表::地表に触れない);
}

/// 始めから地表へ食い込んでいるカプセルは、動けた割合0で接触を返す。
#[test]
fn 始めから地表に触れているカプセルは一歩も動けない() {
    let 答え = 検査用の高さ場を作る()
        .掃引したカプセルが最初に触れる地表を求める(
            大域位置(11.0, 3.6, -19.0),
            大域位置(11.0, 4.6, -19.0),
            メートル::生成する(0.5),
            変位(0.0, -1.0, 0.0),
        )
        .unwrap();
    let 接触 = 接触を取り出す(*答え.値());
    assert_eq!(接触.動けた割合().値(), 0.0);
}

#[test]
fn 読み口は3つの枝で答える() {
    let 持たない世界 = 高さ場の読み口::高さ場を持たない世界;
    let 軸の始点 = 大域位置(11.0, 8.0, -19.0);
    let 軸の終点 = 大域位置(11.0, 9.0, -19.0);
    assert_eq!(
        持たない世界.掃引したカプセルが最初に触れる地表を求める(
            軸の始点,
            軸の終点,
            メートル::生成する(0.5),
            変位(0.0, -4.0, 0.0)
        ),
        掃引したカプセルが最初に触れる地表の問い合わせ結果::高さ場を持たない世界
    );
    let 持つ世界 = 高さ場の読み口::高さ場を持つ世界(検査用の高さ場を作る());
    let 半径が0 =
        持つ世界.掃引したカプセルが最初に触れる地表を求める(軸の始点, 軸の終点, メートル::生成する(0.0), 変位(0.0, -4.0, 0.0));
    assert!(matches!(
        半径が0,
        掃引したカプセルが最初に触れる地表の問い合わせ結果::カプセルの掃引を評価できない(_)
    ));
    let 掃引したカプセルが最初に触れる地表の問い合わせ結果::カプセルの掃引を評価した結果(答え) =
        持つ世界.掃引したカプセルが最初に触れる地表を求める(軸の始点, 軸の終点, メートル::生成する(0.5), 変位(0.0, -4.0, 0.0))
    else {
        panic!("高さ場を持つ世界がカプセルの掃引を評価しなかった");
    };
    assert!(接触を取り出す(*答え.値()).動けた割合().値() > 0.0);
}
