//! 実数の格子添字から、それを含む升目の整数添字を求める工程。担当するのは非負のf64の切り捨てだけである。
//!
//! ワークスペースが数値のasキャストを禁じており、f64から整数への切り捨てを行う安全な変換が標準に無いため、
//! ビットの重みを大きい側から差し引いて整数を組み立てる。
//! 参照: `crates/blitz_engine/src/streaming/chunk_grid.rs`の同型の変換

/// 非負の実数添字の床を、格子添字として使える整数へ写す。負の値・非有限・u32の範囲を超える値は`None`を返す。
pub(super) fn 実数添字の床を格子添字へ変換する(実数添字: f64) -> Option<u32> {
    if !実数添字.is_finite() || !(0.0..4_294_967_296.0).contains(&実数添字) {
        return None;
    }
    let mut 残り = 実数添字.floor();
    let mut 整数 = 0_u32;
    for ビット in (0_u32..32).rev() {
        let 重み = 1_u32 << ビット;
        if 残り >= f64::from(重み) {
            整数 |= 重み;
            残り -= f64::from(重み);
        }
    }
    Some(整数)
}
