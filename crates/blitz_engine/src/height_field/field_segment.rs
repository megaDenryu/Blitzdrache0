//! 高さ場に線分を1本引いて、地表に最初に当たる点を求める問い合わせ。受け取るのは始点と終点の大域ワールド位置、
//! 返すのは最初に当たった地表と、走査が線分のどこまでを調べられたかを表す完全性である。
//!
//! 升目を辿る走査も升目の中の交差の求解も衝突数学層が持ち、この工程が担うのは語彙の写しだけである。
//! 大域の位置を格子原点からの位置へ写し、衝突数学へ自分自身を四隅の高さの供給元として渡し、
//! 返ってきた升目の面を世界の地表の面へ写す。

use blitz_collision::height_field::{
    升目の一辺, 升目の三角形, 升目の格子添字, 線分が地表に最初に当たる点, 線分と高さ場の当たりの結果, 線分の問い合わせエラー, 線分の走査が調べた範囲,
    高さ場の線分の問い合わせ, 高さ場を貫く線分,
};
use blitz_math::大域ワールド位置;

use super::field::高さ場;
use super::field_ground_surface::升目の面を世界の地表の面へ写す;
use super::segment_hit::{線分が最初に当たる地表, 線分と地表の当たり};
use super::triangle_location::地表の三角形の所在;
use crate::world_query::{世界問い合わせ結果, 問い合わせ完全性};

impl 高さ場 {
    /// 始点から終点へ引いた線分が、地表に最初に当たる点を求める。始点が既に地表より下にある線分は
    /// 交差時刻0で当たったものとして返す。高さ場の広がりの外へ出た走査はそこで打ち切られ、
    /// 完全性が「評価できない領域を含む」になる。
    pub fn 線分が最初に当たる地表を求める(
        &self,
        始点: 大域ワールド位置,
        終点: 大域ワールド位置,
    ) -> Result<世界問い合わせ結果<線分が最初に当たる地表>, 線分の問い合わせエラー> {
        let 線分 = 高さ場を貫く線分::生成する(
            self.大域位置を格子原点からの位置へ写す(始点)?,
            self.大域位置を格子原点からの位置へ写す(終点)?,
        );
        let 一辺 = 升目の一辺::生成する(f64::from(self.諸元().格子間隔().値()))?;
        let 結果 = 高さ場の線分の問い合わせ::生成する(self, 一辺).線分が地表に最初に当たる点を求める(&線分)?;
        Ok(self.当たりと調べた範囲を世界の語彙へ写す(結果))
    }

    fn 当たりと調べた範囲を世界の語彙へ写す(
        &self,
        結果: 線分と高さ場の当たりの結果,
    ) -> 世界問い合わせ結果<線分が最初に当たる地表> {
        let 完全性 = match 結果.調べた範囲() {
            線分の走査が調べた範囲::線分の全体を調べた => 問い合わせ完全性::対象範囲を完全に評価できた,
            線分の走査が調べた範囲::調べられない升目で打ち切った => {
                問い合わせ完全性::評価できない領域を含む
            }
        };
        let 当たり = match 結果.最初に当たる点() {
            線分が地表に最初に当たる点::地表に当たらない => 線分が最初に当たる地表::地表に当たらない,
            線分が地表に最初に当たる点::地表に当たる(当たり) => {
                線分が最初に当たる地表::地表に当たる(線分と地表の当たり::生成する(
                    当たり.交差時刻(),
                    升目の面を世界の地表の面へ写す(
                        self.格子原点からの位置を大域位置へ写す(当たり.交差位置()),
                        当たり.地表の面(),
                        升目の添字を所在へ写す(当たり.升目の添字(), 当たり.地表の面().三角形()),
                    ),
                ))
            }
        };
        世界問い合わせ結果::生成する(当たり, 完全性)
    }
}

/// 衝突数学が使う符号付きの升目の添字を、世界の側の所在へ写す。
///
/// 注意: 当たりが返ったということは、その升目の四隅の高さを高さ場が答えたということであり、
/// 添字は必ず非負である。負であれば供給元の実装が壊れているため、無言で代わりの値を返さず止める。
fn 升目の添字を所在へ写す(添字: 升目の格子添字, 三角形: 升目の三角形) -> 地表の三角形の所在 {
    match (u32::try_from(添字.東添字()), u32::try_from(添字.南添字())) {
        (Ok(東添字), Ok(南添字)) => 地表の三角形の所在::生成する(東添字, 南添字, 三角形),
        _ => panic!("当たった升目の添字が負だった(不変条件の破れ): 東{}、南{}", 添字.東添字(), 添字.南添字()),
    }
}
