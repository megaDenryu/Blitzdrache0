//! 大域の水平位置を升目の中の位置へ写す工程と、升目の四隅の高さを混ぜる工程。担当するのはこの2つの計算だけであり、
//! 標本の保持も格子添字での読み出しも持たない。
//!
//! 混ぜ方は双一次(東の比で2回、南の比で1回の線形混合)である。地形メッシュが張る2つの三角形の面と違って
//! 鞍型の升目では描画面から離れるが、接地の土台としては升目の内側で滑らかに変化することを優先する。

use blitz_math::大域ワールド位置;

use super::error::高さ場の広がりの外エラー;
use super::grid_index::実数添字の床を格子添字へ変換する;
use super::specification::高さ場諸元;

/// 問い合わせ位置が属する升目の左手前の格子添字と、その升目の中での比。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 升目の中の位置 {
    pub(super) 東添字: u32,
    pub(super) 南添字: u32,
    pub(super) 東の比: f64,
    pub(super) 南の比: f64,
}

pub(super) fn 大域の水平位置を升目の中の位置へ写す(
    諸元: 高さ場諸元,
    位置: 大域ワールド位置,
) -> Result<升目の中の位置, 高さ場の広がりの外エラー> {
    let 東の大域メートル = 位置.x().値();
    let 南の大域メートル = 位置.z().値();
    let 範囲の外 = 高さ場の広がりの外エラー {
        東の大域メートル,
        南の大域メートル,
    };
    let 格子間隔 = f64::from(諸元.格子間隔().値());
    let 東の実数添字 = (東の大域メートル - 諸元.格子原点の東成分().値()) / 格子間隔;
    let 南の実数添字 = (南の大域メートル - 諸元.格子原点の南成分().値()) / 格子間隔;
    let (東添字, 東の比) = 軸の升目を求める(東の実数添字, 諸元.東方向の格子点数()).ok_or(範囲の外)?;
    let (南添字, 南の比) = 軸の升目を求める(南の実数添字, 諸元.南方向の格子点数()).ok_or(範囲の外)?;
    Ok(升目の中の位置 {
        東添字,
        南添字,
        東の比,
        南の比,
    })
}

/// 1つの軸について、実数添字を升目の左端の格子添字と升目の中の比へ分ける。
/// 最後の格子点ちょうどは1つ手前の升目の右端として扱う。そうしないと格子の縁だけが問い合わせに答えられない。
fn 軸の升目を求める(実数添字: f64, 格子点数: u32) -> Option<(u32, f64)> {
    let 上限の添字 = 格子点数.checked_sub(1)?;
    if !(0.0..=f64::from(上限の添字)).contains(&実数添字) {
        return None;
    }
    let 床 = 実数添字の床を格子添字へ変換する(実数添字)?;
    let 升目の添字 = 床.min(上限の添字.checked_sub(1)?);
    Some((升目の添字, 実数添字 - f64::from(升目の添字)))
}

/// 升目の四隅の高さを、東の比と南の比で混ぜる。手前が南添字、奥が南添字の次であり、左が東添字、右が東添字の次である。
pub(super) fn 四隅の高さを混ぜる(手前左: f64, 手前右: f64, 奥左: f64, 奥右: f64, 東の比: f64, 南の比: f64) -> f64 {
    let 手前 = 手前左 + (手前右 - 手前左) * 東の比;
    let 奥 = 奥左 + (奥右 - 奥左) * 東の比;
    手前 + (奥 - 手前) * 南の比
}
