//! 地表層のタイル1件。担当するのは、エディターが付けたエンジン材質名と、その材質のタイルテクスチャを
//! 1つの組として保つことである。
//!
//! 名前とテクスチャを別々の並びで持たないのは、片方だけを並べ替えたときに材質と絵が入れ替わっても型が通るためである。
//! 名前の検証は`エンジン材質名`が済ませているため、この型は組にすること以外の判定を持たない。

use crate::asset::texture_storage::格納済みテクスチャ;

use super::engine_material_name::エンジン材質名;

#[derive(Debug, Clone, PartialEq)]
pub struct 地表層のタイル {
    材質名: エンジン材質名,
    ベースカラー: 格納済みテクスチャ,
}

impl 地表層のタイル {
    pub fn 生成する(材質名: エンジン材質名, ベースカラー: 格納済みテクスチャ) -> Self {
        Self {
            材質名, ベースカラー
        }
    }

    pub fn 材質名(&self) -> &エンジン材質名 {
        &self.材質名
    }

    pub fn ベースカラー(&self) -> &格納済みテクスチャ {
        &self.ベースカラー
    }
}
