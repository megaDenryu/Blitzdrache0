//! 層から材質への索引。担当するのは、4つの層それぞれがタイルの並びの何番目を指すかを、
//! タイルの件数の内側であることを確かめたうえで保つことである。
//!
//! 実行時に材質名で引く経路を持たないのは、名前の解決を焼く側の1回に閉じるためである。
//! 索引が範囲の外を指す値を作れないようにするため、生成はタイルの件数を必ず受け取る。

use super::error::地表層テクスチャ集エラー;
use super::地表層の数;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 地表層ごとの材質索引 {
    層ごとの索引: [u32; 地表層の数],
}

impl 地表層ごとの材質索引 {
    pub fn 件数の内側であることを確かめて生成する(
        層ごとの索引: [u32; 地表層の数],
        タイルの件数: usize,
    ) -> Result<Self, 地表層テクスチャ集エラー> {
        for (層番号, 索引) in 層ごとの索引.iter().enumerate() {
            let 収まる = usize::try_from(*索引).is_ok_and(|添字| 添字 < タイルの件数);
            if !収まる {
                return Err(地表層テクスチャ集エラー::層の材質索引が範囲外 {
                    層番号,
                    索引: *索引,
                    件数: タイルの件数,
                });
            }
        }
        Ok(Self { 層ごとの索引 })
    }

    /// 層番号を配列の添字として使う並び。層0が草・層1が泥・層2が岩・層3が砂であり、
    /// 地表材質の重みのRGBA成分の並びと同じである。
    pub fn 層ごとの索引(self) -> [u32; 地表層の数] {
        self.層ごとの索引
    }
}
