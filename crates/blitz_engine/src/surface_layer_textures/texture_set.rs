//! 地表層テクスチャ集の実体。担当するのは、材質名で並べたタイルと、層から材質への索引を、
//! 索引が必ずタイルを指す組として保つことである。
//!
//! 材質名の重複をここで拒むのは、重複があると層の名前解決の結果が並びの順に依存し、
//! 焼き直すたびに別のタイルが層へ結びつきうるためである。

use super::error::地表層テクスチャ集エラー;
use super::layer_index::地表層ごとの材質索引;
use super::tile::地表層のタイル;
use super::地表層の数;

#[derive(Debug, Clone, PartialEq)]
pub struct 地表層テクスチャ集 {
    材質ごとのタイル: Vec<地表層のタイル>,
    層ごとの材質索引: 地表層ごとの材質索引,
}

impl 地表層テクスチャ集 {
    pub fn 生成する(
        材質ごとのタイル: Vec<地表層のタイル>,
        層ごとの材質索引: 地表層ごとの材質索引,
    ) -> Result<Self, 地表層テクスチャ集エラー> {
        if 材質ごとのタイル.is_empty() {
            return Err(地表層テクスチャ集エラー::タイルが1枚も無い);
        }
        重複した材質名が無いことを確かめる(&材質ごとのタイル)?;
        地表層ごとの材質索引::件数の内側であることを確かめて生成する(
            層ごとの材質索引.層ごとの索引(),
            材質ごとのタイル.len(),
        )?;
        Ok(Self {
            材質ごとのタイル,
            層ごとの材質索引,
        })
    }

    /// 層が参照する材質名の並びから索引を解決して組み立てる。焼く側がこの1つを通るため、
    /// 名前を解決できないまま実行時形式へ焼ける経路が存在しない。
    pub fn 層が参照する材質名から解決して生成する(
        材質ごとのタイル: Vec<地表層のタイル>,
        層ごとの材質名: [&str; 地表層の数],
    ) -> Result<Self, 地表層テクスチャ集エラー> {
        let mut 層ごとの索引 = [0_u32; 地表層の数];
        for (層番号, 材質名) in 層ごとの材質名.iter().enumerate() {
            let 見つけた = 材質ごとのタイル.iter().position(|タイル| タイル.材質名() == *材質名).ok_or_else(|| {
                地表層テクスチャ集エラー::層が参照する材質名が無い {
                    層番号,
                    材質名: (*材質名).to_string(),
                }
            })?;
            層ごとの索引[層番号] = u32::try_from(見つけた)
                .map_err(|_| 地表層テクスチャ集エラー::タイルの件数が索引の型に収まらない(見つけた))?;
        }
        let 索引 = 地表層ごとの材質索引::件数の内側であることを確かめて生成する(層ごとの索引, 材質ごとのタイル.len())?;
        Self::生成する(材質ごとのタイル, 索引)
    }

    pub fn 材質ごとのタイル(&self) -> &[地表層のタイル] {
        &self.材質ごとのタイル
    }

    pub fn 層ごとの材質索引(&self) -> 地表層ごとの材質索引 {
        self.層ごとの材質索引
    }

    /// 層番号のタイルを引く。索引が件数の内側であることは生成が保証するため、範囲外は到達したらバグである。
    pub fn 層のタイル(&self, 層番号: usize) -> &地表層のタイル {
        let 索引 = self.層ごとの材質索引.層ごとの索引();
        let 添字 = 索引
            .get(層番号)
            .and_then(|値| usize::try_from(*値).ok())
            .and_then(|添字| self.材質ごとのタイル.get(添字));
        match 添字 {
            Some(タイル) => タイル,
            None => panic!("層ごとの材質索引が必ずタイルを指すという不変条件に違反した: 層番号={層番号}"),
        }
    }
}

fn 重複した材質名が無いことを確かめる(一覧: &[地表層のタイル]) -> Result<(), 地表層テクスチャ集エラー> {
    for (番号, タイル) in 一覧.iter().enumerate() {
        if 一覧.iter().take(番号).any(|先行| 先行.材質名() == タイル.材質名()) {
            return Err(地表層テクスチャ集エラー::材質名が重複している(
                タイル.材質名().to_string(),
            ));
        }
    }
    Ok(())
}
