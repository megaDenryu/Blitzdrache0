//! 地表層テクスチャ集の型付きエラー。タイルの並びと、層から材質への索引の解決の失敗をこの1つの語彙で表す。

use thiserror::Error;

#[derive(Debug, Error)]
pub enum 地表層テクスチャ集エラー {
    #[error("地表層テクスチャ集がタイルを1枚も持たない")]
    タイルが1枚も無い,
    #[error("地表層テクスチャ集のタイルの材質名が重複している: {0}")]
    材質名が重複している(String),
    #[error("地表層テクスチャ集のタイルの材質名が空である")]
    材質名が空,
    #[error("層{層番号}が指す材質索引{索引}がタイルの件数{件数}の外である")]
    層の材質索引が範囲外 { 層番号: usize, 索引: u32, 件数: usize },
    #[error("層{層番号}が参照する材質名{材質名}が地表層テクスチャ集に無い")]
    層が参照する材質名が無い { 層番号: usize, 材質名: String },
    #[error("タイルの件数が索引の型に収まらない: {0}")]
    タイルの件数が索引の型に収まらない(usize),
}
