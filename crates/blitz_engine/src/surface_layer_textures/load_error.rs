//! カタログ経由で地表層テクスチャ集アセットを読み込むときに返す型付きエラー。
//!
//! カタログに安定IDの登録が無いことはこの語彙に入らない。登録が無い世界は失敗ではなく
//! 「地表層テクスチャ集を持たない世界」であり、`地表層テクスチャ集の読み口`の枝が表す。

use crate::asset::runtime_format::地表層テクスチャ集実行時形式エラー;
use crate::asset::{アセットIDエラー, 実行時形式のファイルの読み取りの破れ};

#[derive(Debug, thiserror::Error)]
pub enum 地表層テクスチャ集読込エラー {
    #[error("地表層テクスチャ集の安定IDを組み立てられない: {0}")]
    安定IDが不正(#[from] アセットIDエラー),
    #[error("地表層テクスチャ集アセットのファイル読込に失敗した: {0}")]
    ファイル読込失敗(#[from] 実行時形式のファイルの読み取りの破れ),
    #[error("地表層テクスチャ集アセットの形式検査に失敗した: {0}")]
    形式不正(#[from] 地表層テクスチャ集実行時形式エラー),
}
