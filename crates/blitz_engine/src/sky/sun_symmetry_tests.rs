//! 南中を挟んで対称な時刻の対が持つ性質の検査。対の中で高度が等しく方位だけが違うことを確かめる。
//!
//! この性質はシャドウ性能の計測が使う。太陽の方位を固定して高度だけを振る指定が無いため、
//! 高度の効きと方位の効きは同じ高度の対でしか分けられない。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」

#![allow(clippy::unwrap_used)]

use blitz_math::大域秒;

use super::{天空状態, 天空状態を導出する, 空と太陽の方針};
use crate::time::世界時刻;

const 一時間の秒数: f64 = 3_600.0;

/// 計測が対で使う午前側の時刻。相手は南中(12時)を挟んだ`24 - 午前`である。
const 午前側の時刻: [f64; 3] = [7.0, 8.0, 9.0];

fn 導出する(時: f64) -> 天空状態 {
    let 時刻 = 世界時刻::生成する(大域秒::生成する(時 * 一時間の秒数)).unwrap();
    天空状態を導出する(時刻, &空と太陽の方針::既定値()).unwrap()
}

#[test]
fn 南中対称の時刻は同じ高度で違う方位になる() {
    for 午前 in 午前側の時刻 {
        let 午後 = 24.0 - 午前;
        let (朝, 夕) = (導出する(午前), 導出する(午後));
        let 高度差 = (朝.太陽高度().値() - 夕.太陽高度().値()).abs();
        assert!(高度差 < 1e-5, "{午前}時と{午後}時の高度が{高度差}ラジアンだけ違う");
        let 方位差 = (朝.太陽方向().方位().値() - 夕.太陽方向().方位().値()).abs();
        assert!(方位差 > 0.1, "{午前}時と{午後}時の方位が{方位差}ラジアンしか違わない");
    }
}
