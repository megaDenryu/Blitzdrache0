//! 方向光の影を描くかどうかの判別。

use super::昼係数;

/// 方向光の影の有効性。太陽が薄明帯より下へ降りて方向光の強度が0になる間は無効になる。
/// 強度が0になる時刻ちょうどで切り替えるのは、影が消える瞬間に画素の跳びを作らないためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 影の有効性 {
    有効,
    無効,
}

impl 影の有効性 {
    pub(super) fn 昼係数から決める(昼係数: 昼係数) -> Self {
        if 昼係数.昼側か() { Self::有効 } else { Self::無効 }
    }
}
