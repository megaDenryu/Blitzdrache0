//! 天空状態の導出の検査: 決定性・日境界の循環・太陽方向の単位長・有限値・高度の最大と最小。

#![allow(clippy::unwrap_used)]

use blitz_math::大域秒;

use super::{天空状態, 天空状態を導出する, 影の有効性, 空と太陽の方針};
use crate::time::世界時刻;

/// 一日の秒数。代表時刻を「何時」で書くための換算に使う。
const 一時間の秒数: f64 = 3_600.0;
const 一日の秒数: f64 = 86_400.0;

fn 導出する(時: f64) -> 天空状態 {
    let 時刻 = 世界時刻::生成する(大域秒::生成する(時 * 一時間の秒数)).unwrap();
    天空状態を導出する(時刻, &空と太陽の方針::既定値()).unwrap()
}

fn 秒で導出する(秒数: f64) -> 天空状態 {
    let 時刻 = 世界時刻::生成する(大域秒::生成する(秒数)).unwrap();
    天空状態を導出する(時刻, &空と太陽の方針::既定値()).unwrap()
}

#[test]
fn 同一時刻の二回の導出は完全に一致する() {
    for 時 in [0.0, 6.0, 9.0, 12.0, 18.0, 21.0] {
        assert_eq!(導出する(時), 導出する(時), "時刻{時}の導出が二回で食い違った");
    }
}

#[test]
fn 日境界をまたいでも同じ天空状態になる() {
    for 秒数 in [0.0, 21_600.0, 43_200.0, 64_800.0] {
        assert_eq!(秒で導出する(秒数), 秒で導出する(秒数 + 一日の秒数), "秒数{秒数}の翌日が一致しない");
        assert_eq!(秒で導出する(秒数), 秒で導出する(秒数 - 一日の秒数), "秒数{秒数}の前日が一致しない");
    }
}

#[test]
fn 負の世界時刻でも同じ循環に乗る() {
    let 千日前の正午 = 秒で導出する(43_200.0 - 一日の秒数 * 1_000.0);
    assert_eq!(千日前の正午, 秒で導出する(43_200.0));
}

#[test]
fn 太陽方向は常に単位長で全出力が有限になる() {
    for 刻み in 0..48 {
        let 状態 = 秒で導出する(f64::from(刻み) * 一日の秒数 / 48.0);
        let 成分 = 状態.太陽方向().成分();
        let 長さ二乗: f32 = 成分.iter().map(|値| 値 * 値).sum();
        assert!((長さ二乗 - 1.0).abs() < 1e-5, "刻み{刻み}の太陽方向の長さ二乗が{長さ二乗}");
        assert!(有限か(&状態), "刻み{刻み}の天空状態に非有限値がある");
    }
}

#[test]
fn 正午が最も高く真夜中が最も低い() {
    let 高度一覧: Vec<f32> = (0..48)
        .map(|刻み| 秒で導出する(f64::from(刻み) * 一日の秒数 / 48.0).太陽高度().値())
        .collect();
    let 正午 = 導出する(12.0).太陽高度().値();
    let 真夜中 = 導出する(0.0).太陽高度().値();
    assert!(高度一覧.iter().all(|高度| *高度 <= 正午), "正午より高い時刻がある");
    assert!(高度一覧.iter().all(|高度| *高度 >= 真夜中), "真夜中より低い時刻がある");
    assert!(真夜中 < 0.0 && 正午 > 0.0, "正午{正午}と真夜中{真夜中}が地平線をまたいでいない");
}

#[test]
fn 夜は方向光が消えて影が無効になる() {
    let 真夜中 = 導出する(0.0);
    assert_eq!(真夜中.方向光強度().値(), 0.0);
    assert_eq!(真夜中.影の有効性(), 影の有効性::無効);
    let 正午 = 導出する(12.0);
    assert!(正午.方向光強度().値() > 0.0);
    assert_eq!(正午.影の有効性(), 影の有効性::有効);
}

fn 有限か(状態: &天空状態) -> bool {
    let 成分 = 状態.太陽方向().成分();
    let 色 = 状態.方向光色().成分();
    成分.iter().chain(色.iter()).all(|値| 値.is_finite())
        && [
            状態.太陽高度().値(),
            状態.方向光強度().値(),
            状態.環境光強度().値(),
            状態.露出補正段().値(),
            状態.空の係数().太陽天頂角().値(),
            状態.空の係数().濁度().値(),
            状態.昼係数().値(),
        ]
        .iter()
        .all(|値| 値.is_finite())
}
