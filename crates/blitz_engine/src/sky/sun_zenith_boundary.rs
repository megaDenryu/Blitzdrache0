//! 一日の太陽軌道が跨ぐ太陽天頂区間の境界の列挙。担当する工程は「空と太陽の方針と間引きの刻みを受け取り、
//! その世界の一日で太陽の天頂余弦が跨ぐ境界を、跨いだ時刻とともに並べて返す」ことである。
//! 時刻から区間を読むことと跨いだ秒を詰めることは`sun_zenith_boundary_crossing`が持つ。
//!
//! 境界の一覧を検収側の表で持たないために本番と同じ導出へ置く。天頂余弦は空と太陽の方針(緯度・太陽赤緯・
//! 一日の長さ)だけで決まり、区間の分け方は間引きの刻みの設定だけで決まる。どちらかを写した表を別に持つと、
//! 方針や刻みを変えた実行と検収が別の境界を見る。
//!
//! 上りと下りで同じ境界を2度収めないのは、区間の中身が代表天頂余弦だけで決まり、上りと下りで同じ2つの
//! 代表値の間を移るためである。収めるのは一日で最初に跨いだ時刻である。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」

use super::sun_zenith_boundary_crossing::{区間を求める, 跨いだ秒を挟み撃つ};
use super::{天空状態エラー, 太陽天頂区間, 空と太陽の方針, 間引きの刻みの設定};

/// 一日を刻む標本の数。既定の一日ではちょうど1秒に当たる。天頂余弦が1秒で動く量は高々7e-5であり、
/// 刻みの初期値の区間の幅0.01の百分の一に満たないため、隣り合う標本が2つ以上の境界を跨ぐことはない。
/// 跨いだ標本が現れたら刻みが極端に細かいことを意味するため、黙って飛ばさずに型付きの失敗にする。
const 一日の標本数: u32 = 86_400;

/// 一日で跨いだ境界1つ。上側の区間の下端がその境界の天頂余弦であり、1つ下の区間との境目を指す。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 太陽天頂区間の境界 {
    上側の区間: 太陽天頂区間,
    最初に跨いだ一日内秒: f64,
}

impl 太陽天頂区間の境界 {
    pub fn 上側の区間(self) -> 太陽天頂区間 {
        self.上側の区間
    }

    /// 一日の始まりから数えて最初にこの境界を跨いだ秒。段差を撮る実行はこの時刻へ時計を据える。
    pub fn 最初に跨いだ一日内秒(self) -> f64 {
        self.最初に跨いだ一日内秒
    }
}

/// 一日で跨ぐ境界を区間識別の昇順に並べて返す。
pub fn 一日の区間境界を列挙する(
    方針: &空と太陽の方針,
    刻み: 間引きの刻みの設定,
) -> Result<Vec<太陽天頂区間の境界>, 天空状態エラー> {
    let 一日の秒数 = f64::from(方針.天球().一日の長さ().秒数().値());
    let mut 一覧: Vec<太陽天頂区間の境界> = Vec::new();
    let mut 前の秒 = 0.0;
    let mut 前の識別 = 区間を求める(前の秒, 方針, 刻み)?.区間識別();
    for 番号 in 1..=一日の標本数 {
        let 秒 = 一日の秒数 * f64::from(番号) / f64::from(一日の標本数);
        let 識別 = 区間を求める(秒, 方針, 刻み)?.区間識別();
        if 識別 != 前の識別 {
            let 跨いだ数 = 識別.abs_diff(前の識別);
            if 跨いだ数 != 1 {
                return Err(天空状態エラー::値域外("隣り合う標本が跨いだ境界の数", f32::from(跨いだ数)));
            }
            収める(&mut 一覧, 識別.max(前の識別), (前の秒, 前の識別), 秒, 方針, 刻み)?;
        }
        (前の秒, 前の識別) = (秒, 識別);
    }
    一覧.sort_by_key(|境界| 境界.上側の区間.区間識別());
    Ok(一覧)
}

/// まだ収めていない境界だけを一覧へ足す。同じ境界を上りと下りの2回収めないための唯一の関門である。
fn 収める(
    一覧: &mut Vec<太陽天頂区間の境界>,
    上側の識別: u16,
    下側: (f64, u16),
    上側の秒: f64,
    方針: &空と太陽の方針,
    刻み: 間引きの刻みの設定,
) -> Result<(), 天空状態エラー> {
    if 一覧.iter().any(|境界| 境界.上側の区間.区間識別() == 上側の識別) {
        return Ok(());
    }
    一覧.push(太陽天頂区間の境界 {
        上側の区間: 太陽天頂区間::識別から作る(上側の識別, 刻み)?,
        最初に跨いだ一日内秒: 跨いだ秒を挟み撃つ(下側, 上側の秒, 方針, 刻み)?,
    });
    Ok(())
}
