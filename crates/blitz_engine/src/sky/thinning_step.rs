//! 遠方環境の更新を間引く刻みの設定。太陽の天頂余弦の値域をいくつの区間へ分けるかだけを持つ。
//!
//! 区間の数を値オブジェクトで包むのは、本番の焼き上げと診断の出力が同じ1箇所を読み、区間の数の定数が
//! 複製されないようにするためである。複製すると、焼いた刻みと報告した刻みが別々に動きうる。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」

use std::num::NonZeroU16;

/// 区間の数の初期値。値域[-1, +1]を200へ分けるため1区間の幅は0.01である。
/// 最終値は段差の実測とGPU費用の計測から制定する。
const 区間の数の初期値: NonZeroU16 = match NonZeroU16::new(200) {
    Some(値) => 値,
    None => panic!("区間の数の初期値が0である"),
};

/// 太陽天頂区間の数。0を型で禁じるのは、区間が1つも無い刻みでは所属も代表値も定義できないためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 間引きの刻みの設定 {
    区間の数: NonZeroU16,
}

impl 間引きの刻みの設定 {
    pub fn 生成する(区間の数: NonZeroU16) -> Self {
        Self { 区間の数 }
    }

    /// まだ制定していない段階で全世界が読む刻み。組み立てを`生成する`へ通し、値の作り方を1本に保つ。
    pub fn 初期値() -> Self {
        Self::生成する(区間の数の初期値)
    }

    pub fn 区間の数(self) -> NonZeroU16 {
        self.区間の数
    }
}
