//! 方向光の色と強度を時刻へ結びつける設定。

use blitz_math::ラジアン;

use super::daylight_factor::滑らかに移す;
use super::default_constant::確定値;
use super::{天空状態エラー, 太陽光強度, 太陽光色, 昼係数};

/// 太陽が高いときの強度。既存の既定ライティングの方向光強度と同じ値であり、時刻へ配線しても明るさの基準が変わらない。
const 既定の最大強度: f32 = 3.0;
/// 天頂付近の太陽の色。散乱で削られる前の白い光を表す。
const 既定の天頂の色: [f32; 3] = [1.0, 1.0, 1.0];
/// 地平付近の太陽の色。大気を通る行路が長く短波長ほど散乱で失われるため、赤側へ寄る。
const 既定の地平の色: [f32; 3] = [1.0, 0.55, 0.25];
/// 地平の色から天頂の色へ移りきる太陽高度。
const 既定の色遷移高度の度: f32 = 15.0;

/// 太陽光の最大強度と、高度による色の移り方。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 太陽光方針 {
    最大強度: 太陽光強度,
    天頂の色: 太陽光色,
    地平の色: 太陽光色,
    色遷移高度: ラジアン,
}

impl 太陽光方針 {
    pub fn 生成する(
        最大強度: 太陽光強度, 天頂の色: 太陽光色, 地平の色: 太陽光色, 色遷移高度: ラジアン
    ) -> Result<Self, 天空状態エラー> {
        if !色遷移高度.値().is_finite() || 色遷移高度.値() <= 0.0 {
            return Err(天空状態エラー::値域外("色遷移高度", 色遷移高度.値()));
        }
        Ok(Self {
            最大強度,
            天頂の色,
            地平の色,
            色遷移高度,
        })
    }

    pub fn 既定値() -> Self {
        Self {
            最大強度: 確定値(太陽光強度::生成する(既定の最大強度)),
            天頂の色: 確定値(色を作る(既定の天頂の色)),
            地平の色: 確定値(色を作る(既定の地平の色)),
            色遷移高度: ラジアン::度から(既定の色遷移高度の度),
        }
    }

    /// 太陽高度に応じた方向光の色。地平線で地平の色、色遷移高度より上で天頂の色になり、間は滑らかに移る。
    pub fn 高度に応じた色(&self, 太陽高度: ラジアン) -> Result<太陽光色, 天空状態エラー> {
        let 係数 = 滑らかに移す(0.0, self.色遷移高度.値(), 太陽高度.値());
        self.地平の色.混ぜる(&self.天頂の色, 係数)
    }

    /// 昼係数で弱めた方向光の強度。夜は0になる。
    pub fn 昼係数に応じた強度(&self, 昼係数: 昼係数) -> Result<太陽光強度, 天空状態エラー> {
        self.最大強度.弱める(昼係数.値())
    }
}

fn 色を作る(成分: [f32; 3]) -> Result<太陽光色, 天空状態エラー> {
    太陽光色::生成する(成分[0], 成分[1], 成分[2])
}
