//! 一日の跨ぎの列挙を反証可能な形で固定する。期待値に列挙の式を書き写さないのは、写した式が誤っていても
//! 検査が通ってしまうためである。ここが見るのは、跨いだ時刻の前後で本当に区間が変わっていることと、
//! 跨ぐ向きが天頂余弦の動く向きと一致していることと、境界ごとに上りと下りが対で並ぶことである。

#![allow(clippy::unwrap_used)]

use std::num::NonZeroU16;

use super::{
    一日の区間の跨ぎを列挙する, 天空状態を導出する, 太陽天頂区間, 空と太陽の方針, 跨ぎの方向, 間引きの刻みの設定
};
use crate::time::世界時刻;
use blitz_math::大域秒;

fn 刻み(区間の数: u16) -> 間引きの刻みの設定 {
    間引きの刻みの設定::生成する(NonZeroU16::new(区間の数).unwrap())
}

fn 天頂余弦(一日内秒: f64, 方針: &空と太陽の方針) -> f32 {
    let 状態 = 天空状態を導出する(世界時刻::生成する(大域秒::生成する(一日内秒)).unwrap(), 方針).unwrap();
    状態.太陽方向().成分()[1]
}

fn 識別(一日内秒: f64, 方針: &空と太陽の方針, 設定: 間引きの刻みの設定) -> u16 {
    太陽天頂区間::属する区間(天頂余弦(一日内秒, 方針), 設定).unwrap().区間識別()
}

/// 跨いだ秒では上側の区間に入っており、その直前の百万分の一秒では入っていない。
#[test]
fn 跨いだ時刻の前後で区間が変わる() {
    let 方針 = 空と太陽の方針::既定値();
    let 設定 = 刻み(200);
    for 跨ぎ in 一日の区間の跨ぎを列挙する(&方針, 設定).unwrap() {
        let 秒 = 跨ぎ.一日内秒();
        let 上側 = 跨ぎ.上側の区間().区間識別();
        let (跨いだ後, 跨ぐ前) = (識別(秒, &方針, 設定), 識別(秒 - 1.0e-6, &方針, 設定));
        assert_ne!(跨いだ後, 跨ぐ前, "区間識別{上側}の境界を跨いだ前後で区間が同じである");
        assert_eq!(跨いだ後.max(跨ぐ前), 上側, "区間識別{上側}の境界の上側が一致しない");
    }
}

/// 上りの跨ぎでは天頂余弦が増え、下りの跨ぎでは減る。向きの取り違えをこれが反証する。
#[test]
fn 跨ぎの方向は天頂余弦の動く向きと一致する() {
    let 方針 = 空と太陽の方針::既定値();
    for 跨ぎ in 一日の区間の跨ぎを列挙する(&方針, 刻み(200)).unwrap() {
        let 秒 = 跨ぎ.一日内秒();
        let 動き = 天頂余弦(秒 + 1.0, &方針) - 天頂余弦(秒 - 1.0, &方針);
        match 跨ぎ.方向() {
            跨ぎの方向::上り => assert!(動き > 0.0, "上りなのに天頂余弦が{動き}しか動いていない"),
            跨ぎの方向::下り => assert!(動き < 0.0, "下りなのに天頂余弦が{動き}動いている"),
        }
    }
}

/// 既定の一日は天頂余弦が最小から最大へ1往復するため、跨ぐ境界はどれも上りと下りが1回ずつになる。
#[test]
fn 境界ごとに上りと下りが対で並ぶ() {
    let 一覧 = 一日の区間の跨ぎを列挙する(&空と太陽の方針::既定値(), 刻み(200)).unwrap();
    assert!(一覧.len() >= 4, "跨ぎが{}件しか出なかった", 一覧.len());
    assert_eq!(一覧.len() % 2, 0, "跨ぎの件数{}が偶数でない", 一覧.len());
    for 対 in 一覧.chunks_exact(2) {
        assert_eq!(対[0].上側の区間().区間識別(), 対[1].上側の区間().区間識別(), "対の境界が違う");
        assert_eq!(対[0].方向(), 跨ぎの方向::上り);
        assert_eq!(対[1].方向(), 跨ぎの方向::下り);
    }
}

/// 境界の識別は上りだけを見ると重複のない連番になる。太陽の天頂余弦は一日の中で連続に動くため、途中の区間を飛ばせない。
#[test]
fn 上りの識別は重複のない連番である() {
    let 一覧 = 一日の区間の跨ぎを列挙する(&空と太陽の方針::既定値(), 刻み(200)).unwrap();
    let 上り: Vec<u16> = 一覧
        .iter()
        .filter(|跨ぎ| 跨ぎ.方向() == 跨ぎの方向::上り)
        .map(|跨ぎ| 跨ぎ.上側の区間().区間識別())
        .collect();
    for 対 in 上り.windows(2) {
        assert_eq!(対[1], 対[0] + 1, "上りの識別が連番でない");
    }
}

/// 区間が1つだけの刻みでは跨ぎが1つも無い。全時刻が同じ区間に入るためである。
#[test]
fn 区間が一つの刻みは跨ぎを持たない() {
    assert!(一日の区間の跨ぎを列挙する(&空と太陽の方針::既定値(), 刻み(1)).unwrap().is_empty());
}
