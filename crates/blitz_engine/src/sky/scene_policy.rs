//! 空と太陽の設定一式。時刻だけでは決まらない値をシーンが構築時に選ぶ。

use super::atmosphere::大気媒体の物理定数;
use super::{天球の幾何条件, 太陽光の導出係数, 昼夜の移り方の係数, 空の描画設定};

/// 天空状態の導出が時刻のほかに必要とする設定一式。同じ方針と同じ世界時刻からは常に同じ天空状態が得られる。
/// 大気媒体の物理定数だけは天空状態の導出に使わず、プリコンピュートのベイク済み画像の生成入力としてレンダラーへ下ろす。
/// それでもこの束が持つのは、どちらもその世界の空を決める時刻非依存の設定であり、世界ごとに別々の出どころへ散らさないためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 空と太陽の設定一式 {
    天球: 天球の幾何条件,
    太陽光: 太陽光の導出係数,
    昼夜: 昼夜の移り方の係数,
    空描画: 空の描画設定,
    大気媒体: 大気媒体の物理定数,
}

impl 空と太陽の設定一式 {
    /// 各方針は自身の生成で値域を検証済みであるため、束ねる操作は失敗しない。
    pub fn 生成する(天球: 天球の幾何条件, 太陽光: 太陽光の導出係数, 昼夜: 昼夜の移り方の係数, 空描画: 空の描画設定, 大気媒体: 大気媒体の物理定数) -> Self {
        Self {
            天球, 太陽光, 昼夜, 空描画, 大気媒体
        }
    }

    pub fn 既定値() -> Self {
        Self {
            天球: 天球の幾何条件::既定値(),
            太陽光: 太陽光の導出係数::既定値(),
            昼夜: 昼夜の移り方の係数::既定値(),
            空描画: 空の描画設定::既定値(),
            大気媒体: 大気媒体の物理定数::地球標準(),
        }
    }

    pub fn 大気媒体(&self) -> 大気媒体の物理定数 {
        self.大気媒体
    }

    pub fn 天球(&self) -> 天球の幾何条件 {
        self.天球
    }

    pub fn 太陽光(&self) -> 太陽光の導出係数 {
        self.太陽光
    }

    pub fn 昼夜(&self) -> 昼夜の移り方の係数 {
        self.昼夜
    }

    pub fn 空描画(&self) -> 空の描画設定 {
        self.空描画
    }
}
