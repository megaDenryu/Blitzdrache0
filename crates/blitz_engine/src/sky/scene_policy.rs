//! 空と太陽の方針。時刻だけでは決まらない値をシーンが構築時に選ぶ。

use super::{天球方針, 太陽光方針, 昼夜方針, 濁度, 空描画方針};

/// 天空状態の導出が時刻のほかに必要とする設定一式。同じ方針と同じ世界時刻からは常に同じ天空状態が得られる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 空と太陽の方針 {
    天球: 天球方針,
    太陽光: 太陽光方針,
    昼夜: 昼夜方針,
    濁度: 濁度,
    空描画: 空描画方針,
}

impl 空と太陽の方針 {
    /// 各方針は自身の生成で値域を検証済みであるため、束ねる操作は失敗しない。
    pub fn 生成する(天球: 天球方針, 太陽光: 太陽光方針, 昼夜: 昼夜方針, 濁度: 濁度, 空描画: 空描画方針) -> Self {
        Self {
            天球,
            太陽光,
            昼夜,
            濁度,
            空描画,
        }
    }

    pub fn 既定値() -> Self {
        Self {
            天球: 天球方針::既定値(),
            太陽光: 太陽光方針::既定値(),
            昼夜: 昼夜方針::既定値(),
            濁度: 濁度::晴天(),
            空描画: 空描画方針::既定値(),
        }
    }

    pub fn 天球(&self) -> 天球方針 {
        self.天球
    }

    pub fn 太陽光(&self) -> 太陽光方針 {
        self.太陽光
    }

    pub fn 昼夜(&self) -> 昼夜方針 {
        self.昼夜
    }

    pub fn 濁度(&self) -> 濁度 {
        self.濁度
    }

    pub fn 空描画(&self) -> 空描画方針 {
        self.空描画
    }
}
