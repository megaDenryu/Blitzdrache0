//! 昼と夜を連続してつなぐ係数。

use blitz_math::ラジアン;

/// 太陽高度が薄明帯を横切る間に0から1へ滑らかに移る係数。夜が0、昼が1である。
/// 方向光の強度・環境光・露出補正段はこの1つの係数から導くため、時刻を動かしても不連続な跳びが出ない。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 昼係数(f32);

impl 昼係数 {
    /// 太陽高度が薄明帯の下端(地平線から下へ幅のぶん)で0、上端(地平線から上へ幅のぶん)で1になるよう滑らかに移す。
    pub(super) fn 太陽高度から求める(太陽高度: ラジアン, 薄明帯の幅: ラジアン) -> Self {
        let 幅 = 薄明帯の幅.値();
        Self(滑らかに移す(-幅, 幅, 太陽高度.値()))
    }

    pub fn 値(&self) -> f32 {
        self.0
    }

    /// 太陽光が働く時間帯かどうか。係数が0の間は方向光の強度も0になる。
    pub fn 昼側か(&self) -> bool {
        self.0 > 0.0
    }
}

/// 下端で0、上端で1になる三次の滑らかな移行(smoothstep)。両端で傾きが0になるため、係数の時間変化に折れ目が出ない。
///
/// 前提: 上端は下端より大きい(薄明帯の幅と色遷移高度はどちらも正であることを方針の生成時に検証している)。
/// 前提が破れた場合に0除算で非有限値を作らないよう、幅が0以下のときは階段関数として扱う。
pub(super) fn 滑らかに移す(下端: f32, 上端: f32, 値: f32) -> f32 {
    if 上端 <= 下端 {
        return if 値 < 下端 { 0.0 } else { 1.0 };
    }
    let 正規化 = ((値 - 下端) / (上端 - 下端)).clamp(0.0, 1.0);
    正規化 * 正規化 * (3.0 - 2.0 * 正規化)
}
