//! 空中遠近ボリュームを作り直すかどうかを値の比較で決めるための鍵。
//! スカイビューキーに、太陽の向きの3成分とカメラの視錐台の向きと最遠距離を足したものである。
//!
//! 太陽の向きを天頂余弦だけでなく3成分で持つのは、空中遠近ボリュームの値が太陽の3次元の向きに依存するためである。
//! 積分が位相関数へ視線と太陽の内積を使い、ボリュームはワールドのカメラ視錐台に固定されているため、太陽の高度が同じまま
//! 方位が変わればボクセルの値が変わる。スカイビューLUTは横軸が太陽に対する相対方位であり天頂余弦だけで足りるが、
//! その省略を空中遠近へ継承することはできない。
//!
//! 天頂余弦がスカイビューキーの中と重複するのを受け入れるのは、鍵をそれ自身で読めるようにするためである。
//! 重複を避けるには「太陽の水平成分だけを足せば足りる」という、スカイビューキーの天頂余弦が太陽の向きの天頂成分に
//! 等しいという型の外にある関係へ依存する。関係を型で保証できないため、単純な形を採る。
//!
//! カメラの位置を鍵へ入れないのは、ボリュームが観測高度を世界の方針から取り、カメラから受け取るのが向きと射影だけ
//! だからである。位置を入れるとカメラが平行移動しただけで焼き直すことになり、大域原点の移動でも鍵が変わって
//! カメラ相対契約が破れる。
//!
//! 視錐台を4隅でなく基準と2つの差分で持つのは、遠平面上の点はクリップ座標のwが一定であるため向きの写像が
//! アフィンになり、この3つで厳密に表せるからである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「更新の決定性」

use blitz_math::メートル;

use super::{スカイビューキー, 太陽方向};

/// 空中遠近ボリュームの中身を決める値の組。浮動小数をビット表現で持つ理由はスカイビューキーと同じである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct 空中遠近キー {
    スカイビュー: スカイビューキー,
    太陽の向きのビット: [u32; 3],
    基準の向きのビット: [u32; 3],
    横の差分のビット: [u32; 3],
    縦の差分のビット: [u32; 3],
    最遠距離のビット: u32,
}

impl 空中遠近キー {
    pub fn 導く(
        スカイビュー: スカイビューキー,
        太陽: 太陽方向,
        基準の向き: [f32; 3],
        横の差分: [f32; 3],
        縦の差分: [f32; 3],
        最遠距離: メートル,
    ) -> Self {
        Self {
            スカイビュー,
            太陽の向きのビット: 太陽.成分().map(f32::to_bits),
            基準の向きのビット: 基準の向き.map(f32::to_bits),
            横の差分のビット: 横の差分.map(f32::to_bits),
            縦の差分のビット: 縦の差分.map(f32::to_bits),
            最遠距離のビット: 最遠距離.値().to_bits(),
        }
    }

    /// スカイビューの部分だけを取り出す。透過率・多重散乱・スカイビューを焼き直すかどうかはこちらだけで決まる。
    pub fn スカイビューの鍵(&self) -> スカイビューキー {
        self.スカイビュー
    }
}
