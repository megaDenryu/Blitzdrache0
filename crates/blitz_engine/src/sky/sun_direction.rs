//! 太陽の向きを表す単位ベクトル。

use blitz_math::ラジアン;

use super::天空状態エラー;

/// 地表から太陽へ向かう単位ベクトル。ワールド軸は X が東、Y が天頂、Z が南であり、北は Z の負の向きである。
/// 不変条件: 3成分は有限であり、長さが1である(生成時に正規化する)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 太陽方向 {
    成分: [f32; 3],
}

impl 太陽方向 {
    pub fn 生成する(東: f32, 天頂: f32, 南: f32) -> Result<Self, 天空状態エラー> {
        let 成分 = [東, 天頂, 南];
        let 長さ二乗: f32 = 成分.iter().map(|値| 値 * 値).sum();
        if !長さ二乗.is_finite() || 長さ二乗 <= f32::EPSILON {
            return Err(天空状態エラー::太陽方向が単位ベクトルでない);
        }
        let 逆長さ = 長さ二乗.sqrt().recip();
        Ok(Self {
            成分: 成分.map(|値| 値 * 逆長さ),
        })
    }

    pub fn 成分(&self) -> [f32; 3] {
        self.成分
    }

    /// 地平面からの仰角。天頂成分が単位ベクトルの正弦であることから直接求める。
    pub fn 高度(&self) -> ラジアン {
        ラジアン::生成する(self.成分[1].clamp(-1.0, 1.0).asin())
    }

    /// 真北から東回りに測った方位角。0以上2π未満であり、真北が0、真東がπ/2である。
    /// ワールドのZ軸は南を向くため、北成分は南成分の符号を反転して得る。
    /// 高度と別に持つのは、同じ高度で方位だけが違う時刻の対を計測の条件として区別するためである。
    pub fn 方位(&self) -> ラジアン {
        let 方位 = self.成分[0].atan2(-self.成分[2]);
        ラジアン::生成する(if 方位 < 0.0 { 方位 + std::f32::consts::TAU } else { 方位 })
    }
}
