//! 方針と値オブジェクトが値域外を拒むことと、既定でない方針でも導出が成り立つことの検査。

#![allow(clippy::unwrap_used)]

use blitz_math::{ラジアン, 大域秒};

use super::{
    天球方針, 天空状態を導出する, 太陽光強度, 太陽光方針, 太陽光色, 昼夜方針, 濁度, 環境光強度, 空と太陽の方針, 露出補正段
};
use crate::time::{一日の長さ, 世界時刻};

#[test]
fn 直角を超える緯度と赤緯を拒む() {
    let 一日 = 一日の長さ::地球の一日();
    assert!(天球方針::生成する(ラジアン::度から(91.0), ラジアン::度から(0.0), 一日).is_err());
    assert!(天球方針::生成する(ラジアン::度から(0.0), ラジアン::度から(-91.0), 一日).is_err());
    assert!(天球方針::生成する(ラジアン::度から(90.0), ラジアン::度から(23.4), 一日).is_ok());
}

#[test]
fn 正でない薄明帯の幅と色遷移高度を拒む() {
    assert!(昼夜方針::生成する(ラジアン::度から(0.0), 昼の環境光(), 夜の環境光(), 段(0.0), 段(2.0)).is_err());
    assert!(太陽光方針::生成する(強度(3.0), 白(), 白(), ラジアン::度から(-1.0)).is_err());
}

#[test]
fn 値域外の値オブジェクトを拒む() {
    assert!(濁度::生成する(0.5).is_err());
    assert!(濁度::生成する(10.5).is_err());
    assert!(太陽光強度::生成する(-0.1).is_err());
    assert!(環境光強度::生成する(1.1).is_err());
    assert!(太陽光色::生成する(1.0, -0.1, 1.0).is_err());
    assert!(露出補正段::生成する(f32::NAN).is_err());
}

/// 赤道で赤緯0の正午は太陽が天頂に来る。既定でない方針を組み立てて導出が成り立つことと、球面計算の向きを同時に固定する。
#[test]
fn 赤道の正午は太陽が天頂へ来る() {
    let 天球 = 天球方針::生成する(ラジアン::度から(0.0), ラジアン::度から(0.0), 一日の長さ::地球の一日()).unwrap();
    let 方針 = 空と太陽の方針::生成する(天球, 太陽光方針::既定値(), 昼夜方針::既定値(), 濁度::晴天());
    let 正午 = 世界時刻::生成する(大域秒::生成する(43_200.0)).unwrap();
    let 状態 = 天空状態を導出する(正午, &方針).unwrap();
    let 天頂成分 = 状態.太陽方向().成分()[1];
    assert!((天頂成分 - 1.0).abs() < 1e-5, "天頂成分が{天頂成分}");
    assert!((状態.太陽高度().値().to_degrees() - 90.0).abs() < 1e-3);
}

/// 日の出のころに太陽が東へ来る。東西の取り違えは絵にしてからでは気づきにくいため、成分の符号を固定する。
#[test]
fn 日の出の太陽は東にある() {
    let 方針 = 空と太陽の方針::既定値();
    let 日の出 = 世界時刻::生成する(大域秒::生成する(21_600.0)).unwrap();
    let 成分 = 天空状態を導出する(日の出, &方針).unwrap().太陽方向().成分();
    assert!(成分[0] > 0.99, "東成分が{}", 成分[0]);
}

