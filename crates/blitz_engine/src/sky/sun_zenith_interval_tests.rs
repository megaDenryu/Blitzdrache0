//! 太陽天頂区間の所属と代表値を反証可能な形で固定する。境界の標本に単精度で正確に表せる値だけを選ぶのは、
//! 境界の実数値を単精度へ丸めた点がどちら側へ落ちるかを見ても丸めの向きしか分からないためである。
//! ここが見るのは「所属を決める比較が半開区間になっているか」である。

#![allow(clippy::unwrap_used)]

use std::num::NonZeroU16;

use super::{太陽天頂区間, 間引きの刻みの設定};

fn 刻み(区間の数: u16) -> 間引きの刻みの設定 {
    間引きの刻みの設定::生成する(NonZeroU16::new(区間の数).unwrap())
}

fn 識別(天頂余弦: f32, 区間の数: u16) -> u16 {
    太陽天頂区間::属する区間(天頂余弦, 刻み(区間の数)).unwrap().区間識別()
}

#[test]
fn 初期値は二百区間である() {
    assert_eq!(間引きの刻みの設定::初期値().区間の数().get(), 200);
}

/// 単精度で正確に表せる境界の点は、その境界を下端とする区間へ入る(半開区間の下端を含む側)。
#[test]
fn 境界ちょうどは上側の区間へ入る() {
    for (天頂余弦, 期待) in [(-1.0, 0), (-0.5, 50), (0.0, 100), (0.25, 125), (0.75, 175)] {
        assert_eq!(識別(天頂余弦, 200), 期待, "天頂余弦{天頂余弦}");
    }
}

/// 境界のすぐ下の単精度は1つ下の区間へ入る。上の検査と対にすることで、比較が上端を含む側へ倒れていないことを見る。
#[test]
fn 境界の直下は一つ下の区間へ入る() {
    for (境界, 期待) in [(0.25_f32, 124), (0.5_f32, 149), (0.75_f32, 174)] {
        assert_eq!(識別(f32::from_bits(境界.to_bits() - 1), 200), 期待, "境界{境界}");
    }
}

#[test]
fn 値域の上端はいちばん上の区間へ入る() {
    assert_eq!(識別(1.0, 200), 199);
    assert_eq!(識別(1.0, 4), 3);
}

/// 単位ベクトルの正規化の丸めで値域をわずかに超えた入力も、両端の区間から出ない。
#[test]
fn 値域を外れた入力は両端の区間へ収まる() {
    assert_eq!(識別(1.5, 200), 199);
    assert_eq!(識別(-1.5, 200), 0);
}

#[test]
fn 非有限の天頂余弦を拒む() {
    for 値 in [f32::NAN, f32::INFINITY, f32::NEG_INFINITY] {
        assert!(太陽天頂区間::属する区間(値, 刻み(200)).is_err(), "{値}");
    }
}

#[test]
fn 代表天頂余弦は区間の中央である() {
    let 設定 = 刻み(200);
    let 代表 = |天頂余弦: f32| 太陽天頂区間::属する区間(天頂余弦, 設定).unwrap().代表天頂余弦().値();
    assert!((代表(-1.0) - (-0.995)).abs() < 1.0e-6, "{}", 代表(-1.0));
    assert!((代表(0.0) - 0.005).abs() < 1.0e-6, "{}", 代表(0.0));
    assert!((代表(1.0) - 0.995).abs() < 1.0e-6, "{}", 代表(1.0));
}

/// 区間が1つだけの刻みでは、どの天頂余弦も同じ区間に入り代表値は値域の中央になる。
#[test]
fn 区間が一つの刻みは全入力を同じ代表値へ写す() {
    let 設定 = 刻み(1);
    for 値 in [-1.0, -0.3, 0.0, 0.7, 1.0] {
        let 区間 = 太陽天頂区間::属する区間(値, 設定).unwrap();
        assert_eq!(区間.区間識別(), 0);
        assert!((区間.代表天頂余弦().値()).abs() < 1.0e-6);
    }
}

/// 代表値を入力へ戻すと同じ区間へ戻る。戻らない標本があれば、所属の探索と代表値の導出が別の刻みを見ている。
/// 期待値に導出の式を書き写さないのは、写した式が誤っていても検査が通ってしまうためである。
#[test]
fn 代表天頂余弦は同じ区間へ戻る() {
    for 区間の数 in [1, 2, 3, 200, 4096] {
        let 設定 = 刻み(区間の数);
        for 番号 in 0_u16..=400 {
            let 天頂余弦 = f32::from(番号) / 200.0 - 1.0;
            let 区間 = 太陽天頂区間::属する区間(天頂余弦, 設定).unwrap();
            let 戻り = 太陽天頂区間::属する区間(区間.代表天頂余弦().値(), 設定).unwrap();
            assert_eq!(戻り, 区間, "区間の数{区間の数}の標本{天頂余弦}");
        }
    }
}
