//! 一日の区間境界の列挙を反証可能な形で固定する。期待値に列挙の式を書き写さないのは、写した式が誤っていても
//! 検査が通ってしまうためである。ここが見るのは、列挙が跨いだ時刻の前後で本当に区間が変わっていることと、
//! 境界に重複も飛びも無いことである。

#![allow(clippy::unwrap_used)]

use std::num::NonZeroU16;

use super::{
    一日の区間境界を列挙する, 天空状態を導出する, 太陽天頂区間, 空と太陽の方針, 間引きの刻みの設定
};
use crate::time::世界時刻;
use blitz_math::大域秒;

fn 刻み(区間の数: u16) -> 間引きの刻みの設定 {
    間引きの刻みの設定::生成する(NonZeroU16::new(区間の数).unwrap())
}

fn 識別(一日内秒: f64, 方針: &空と太陽の方針, 設定: 間引きの刻みの設定) -> u16 {
    let 状態 = 天空状態を導出する(世界時刻::生成する(大域秒::生成する(一日内秒)).unwrap(), 方針).unwrap();
    太陽天頂区間::属する区間(状態.太陽方向().成分()[1], 設定).unwrap().区間識別()
}

/// 跨いだ秒では上側の区間に入っており、その直前の十億分の一秒では入っていない。
#[test]
fn 跨いだ時刻の前後で区間が変わる() {
    let 方針 = 空と太陽の方針::既定値();
    let 設定 = 刻み(200);
    for 境界 in 一日の区間境界を列挙する(&方針, 設定).unwrap() {
        let 秒 = 境界.最初に跨いだ一日内秒();
        let 上側 = 境界.上側の区間().区間識別();
        let 跨いだ後 = 識別(秒, &方針, 設定);
        let 跨ぐ前 = 識別(秒 - 1.0e-6, &方針, 設定);
        assert_ne!(跨いだ後, 跨ぐ前, "区間識別{上側}の境界を跨いだ前後で区間が同じである");
        assert_eq!(跨いだ後.max(跨ぐ前), 上側, "区間識別{上側}の境界の上側が一致しない");
    }
}

/// 境界の識別は重複せず、連続した整数の並びになる。太陽の天頂余弦は一日の中で最小から最大まで連続に動くため、
/// 途中の区間を飛ばすことはありえない。
#[test]
fn 境界の識別は重複のない連番である() {
    let 一覧 = 一日の区間境界を列挙する(&空と太陽の方針::既定値(), 刻み(200)).unwrap();
    assert!(一覧.len() >= 2, "境界が{}個しか出なかった", 一覧.len());
    for 対 in 一覧.windows(2) {
        assert_eq!(対[1].上側の区間().区間識別(), 対[0].上側の区間().区間識別() + 1, "境界の識別が連番でない");
    }
}

/// 境界の天頂余弦は、緯度35度・太陽赤緯0度の一日が到達する天頂余弦の帯の内側に収まる。
/// 帯の端そのものは跨がないため、両端の区間の境界は列挙に入らない。
#[test]
fn 境界は一日の天頂余弦の帯の内側にある() {
    let 方針 = 空と太陽の方針::既定値();
    let 設定 = 刻み(200);
    let 一覧 = 一日の区間境界を列挙する(&方針, 設定).unwrap();
    let 最大の天頂余弦 = 方針.天球().緯度().値().cos();
    for 境界 in 一覧 {
        let 値 = 境界.上側の区間().下端の天頂余弦();
        assert!(値 > -最大の天頂余弦 && 値 < 最大の天頂余弦, "境界の天頂余弦{値}が一日の帯の外にある");
    }
}

/// 区間が1つだけの刻みでは境界が1つも無い。全時刻が同じ区間に入るためである。
#[test]
fn 区間が一つの刻みは境界を持たない() {
    assert!(一日の区間境界を列挙する(&空と太陽の方針::既定値(), 刻み(1)).unwrap().is_empty());
}
