//! 空中遠近キーが太陽の向きの違いを取りこぼさないことの検査。
//!
//! 見るのは「太陽の天頂余弦が同じで方位だけが違う2つの向き」である。この対はスカイビューキーを等しくしたまま
//! 空中遠近ボリュームの値を変える唯一の対であり、鍵が太陽の向きを天頂余弦だけで持っていると通ってしまう。

#![allow(clippy::unwrap_used)]

use blitz_math::メートル;

use super::atmosphere::大気媒体方針;
use super::{スカイビューキー, 太陽方向, 空中遠近キー};

/// カメラの視錐台と最遠距離を固定し、太陽の向きだけを変えて鍵を作る。値は前を向いた透視カメラの向きの組であり、
/// 大きさそのものに意味は無い。
fn 太陽の向きだけを変えた鍵(太陽: 太陽方向) -> 空中遠近キー {
    let スカイビュー = スカイビューキー::導く(大気媒体方針::地球標準().静的キー(), 太陽.成分()[1], メートル::生成する(2.0));
    空中遠近キー::導く(
        スカイビュー,
        太陽,
        [0.0, 0.0, -1.0],
        [1.6, 0.0, 0.0],
        [0.0, -0.9, 0.0],
        メートル::生成する(2000.0),
    )
}

/// 東の空と西の空で同じ高度にある太陽。南中を対称にまたぐ時角hと-hがこの対に当たる。
fn 同じ高度で方位が違う太陽の対() -> (太陽方向, 太陽方向) {
    let 東 = 太陽方向::生成する(0.6, 0.8, 0.0).unwrap();
    let 西 = 太陽方向::生成する(-0.6, 0.8, 0.0).unwrap();
    (東, 西)
}

/// この対がスカイビューキーを等しくすることを先に固定する。スカイビューLUTの横軸が太陽に対する相対方位であるため
/// 等しくて正しく、その省略を空中遠近が継承していないことが次の検査の意味になる。
#[test]
fn 同じ高度で方位が違う太陽はスカイビューキーを等しくする() {
    let (東, 西) = 同じ高度で方位が違う太陽の対();
    assert_eq!(東.成分()[1], 西.成分()[1]);
    let 鍵 = |太陽: 太陽方向| スカイビューキー::導く(大気媒体方針::地球標準().静的キー(), 太陽.成分()[1], メートル::生成する(2.0));
    assert_eq!(鍵(東), 鍵(西));
}

/// 空中遠近ボリュームの散乱は位相関数へ視線と太陽の内積を使い、ボリュームはワールドのカメラ視錐台に固定されている。
/// 方位が変われば同じボクセルの値が変わるため、鍵も変わらなければ古いボリュームを引き続ける。
#[test]
fn 同じ高度で方位が違う太陽は空中遠近キーを違える() {
    let (東, 西) = 同じ高度で方位が違う太陽の対();
    assert_ne!(太陽の向きだけを変えた鍵(東), 太陽の向きだけを変えた鍵(西));
}

/// 同じ太陽の向きからは同じ鍵が出る。方位を足したことで鍵が毎回違う値になっていないことを見る。
#[test]
fn 同じ太陽の向きは同じ空中遠近キーへ写る() {
    let (東, _) = 同じ高度で方位が違う太陽の対();
    assert_eq!(太陽の向きだけを変えた鍵(東), 太陽の向きだけを変えた鍵(東));
}
