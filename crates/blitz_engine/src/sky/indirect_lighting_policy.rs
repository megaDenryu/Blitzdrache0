//! 世界ごとの間接照明の方針と、そこからレンダラーの契約を作る境界。その世界の表面へ届く間接光を、
//! どの供給元が答えるかを世界が宣言する。
//!
//! 空方針と別の型にするのは、空背景の有無と表面への間接照明が独立だからである。屋内の世界は空を描かずに
//! 間接照明を持ちうるし、空を描かない起動指定は背景だけを止める。`--no-sky`で間接照明が定数近似へ
//! 無言で戻ることはしない(参照: `_doc/設計/放射輝度問い合わせ階層.md`「世界の間接照明方針と契約の2枝(3-Ic)」)。
//!
//! 世界の語彙とレンダラーの語彙を分けるのは、レンダラーが「世界」を知らないためである。世界が宣言するのは方針、
//! レンダラーが構築するのは契約であり、その写しはこの型が1箇所で持つ。契約が成立するかどうかの判定も、
//! 判定に要る「その世界が大気の媒体を持つか」を知っているこの境界だけが行える。

use blitz_render::indirect_lighting::{照明問い合わせ契約, 間接照明契約エラー};

/// 世界が宣言する間接照明の供給元。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 世界の間接照明方針 {
    /// 方向も位置も問わない旧来の定数間接近似。環境光係数だけが間接光を代表する。
    定数近似,
    /// 天空から焼いた遠方環境を終端の供給元にする。拡散照度と鏡面畳込みをそこから導く。
    天空の遠方環境,
}

impl 世界の間接照明方針 {
    /// レンダラーが起動時に構築する契約へ写す。方針と契約は1対1に対応する。
    ///
    /// 大気の媒体を持たない世界で天空の遠方環境を選ぶことは型付きの失敗にする。遠方環境はスカイビューの
    /// ベイク済み画像を読んで焼くため、媒体が無ければ焼ける元が1つも無い。定数近似へは戻さない。
    /// 空を描くかどうかはこの判定に入らない(`--no-sky`は背景だけを止め、間接照明の供給元を変えない)。
    pub fn 照明問い合わせ契約へ写す(self, 大気媒体あり: bool) -> Result<照明問い合わせ契約, 間接照明契約エラー> {
        match (self, 大気媒体あり) {
            (Self::定数近似, _) => Ok(照明問い合わせ契約::定数近似),
            (Self::天空の遠方環境, true) => Ok(照明問い合わせ契約::遠方環境LambertGGX),
            (Self::天空の遠方環境, false) => Err(間接照明契約エラー::大気のベイク済み画像なし),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 定数近似は大気の有無によらず定数近似の契約になる() {
        for 大気媒体あり in [true, false] {
            assert_eq!(
                世界の間接照明方針::定数近似.照明問い合わせ契約へ写す(大気媒体あり),
                Ok(照明問い合わせ契約::定数近似)
            );
        }
    }

    #[test]
    fn 天空の遠方環境は大気の媒体があれば遠方環境の契約になる() {
        assert_eq!(
            世界の間接照明方針::天空の遠方環境.照明問い合わせ契約へ写す(true),
            Ok(照明問い合わせ契約::遠方環境LambertGGX)
        );
    }

    #[test]
    fn 天空の遠方環境で大気の媒体が無ければ型付きの失敗になる() {
        assert_eq!(
            世界の間接照明方針::天空の遠方環境.照明問い合わせ契約へ写す(false),
            Err(間接照明契約エラー::大気のベイク済み画像なし)
        );
    }
}
