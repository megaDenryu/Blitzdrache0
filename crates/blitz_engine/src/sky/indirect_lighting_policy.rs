//! 世界ごとの間接照明の方針。その世界の表面へ届く間接光を、どの供給元が答えるかを世界が宣言する。
//!
//! 空方針と別の型にするのは、空背景の有無と表面への間接照明が独立だからである。屋内の世界は空を描かずに
//! 間接照明を持ちうるし、空を描かない起動指定は背景だけを止める。`--no-sky`で間接照明が定数近似へ
//! 無言で戻ることはしない(参照: `_doc/設計/放射輝度問い合わせ階層.md`「世界の間接照明方針と契約の2枝(3-Ic)」)。
//!
//! 世界の語彙とレンダラーの語彙を分けるのは、レンダラーが「世界」を知らないためである。世界が宣言するのは方針、
//! レンダラーが構築するのは契約であり、その写しはこの型が1箇所で持つ。

use blitz_render::indirect_lighting::照明問い合わせ契約;

/// 世界が宣言する間接照明の供給元。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 世界の間接照明方針 {
    /// 方向も位置も問わない旧来の定数間接近似。環境光係数だけが間接光を代表する。
    定数近似,
    /// 天空から焼いた遠方環境を終端の供給元にする。拡散照度と鏡面畳込みをそこから導く。
    天空の遠方環境,
}

impl 世界の間接照明方針 {
    /// レンダラーが起動時に構築する契約へ写す。方針と契約は1対1に対応する。
    pub fn 照明問い合わせ契約へ写す(self) -> 照明問い合わせ契約 {
        match self {
            Self::定数近似 => 照明問い合わせ契約::定数近似,
            Self::天空の遠方環境 => 照明問い合わせ契約::遠方環境LambertGGX,
        }
    }
}
