//! 空パスが方向ごとの放射輝度を評価するために要る係数一式と、その導出。

use blitz_math::ラジアン;

use super::hosek_wilkie;
use super::{天空状態, 天空状態エラー, 放射輝度色, 昼係数, 空と太陽の方針};

/// Hosek-Wilkie解析近似の方向係数(9個×RGB3チャネル)と放射輝度スケール、および夜側へ寄せるための項。
/// 同じ天空状態と同じ方針からは常に同じ値が得られる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 空放射輝度係数 {
    方向係数: [[f32; hosek_wilkie::チャネル数]; hosek_wilkie::係数数],
    放射輝度スケール: [f32; hosek_wilkie::チャネル数],
    夜空放射輝度: 放射輝度色,
    昼係数: 昼係数,
    太陽円盤放射輝度: 放射輝度色,
    太陽円盤角半径: ラジアン,
}

impl 空放射輝度係数 {
    /// 天空状態が運ぶ太陽天頂角と濁度、方針が持つ地表アルベドと倍率から係数を焼く。
    ///
    /// 注意: 太陽高度が0未満の領域は解析近似の定義域外であるため、高度を0で頭打ちにしてから引き当てる。
    /// 定義域外を外挿する代わりに、評価の時点で昼係数によって夜空の最小項へ連続に寄せる。
    pub fn 導出する(状態: &天空状態, 方針: &空と太陽の方針) -> Result<Self, 天空状態エラー> {
        let 描画 = 方針.空描画();
        let 濁度 = 状態.空の係数().濁度().値();
        let アルベド = 描画.地表アルベド().値();
        let 太陽高度 = 定義域内の太陽高度(状態.空の係数().太陽天頂角());
        let 方向係数 = hosek_wilkie::方向係数を焼く(濁度, アルベド, 太陽高度);
        let 素の放射輝度 = hosek_wilkie::放射輝度スケールを焼く(濁度, アルベド, 太陽高度);
        let 放射輝度スケール = 素の放射輝度.map(|値| 値 * 描画.放射輝度倍率());
        有限性を確かめる(&方向係数, &放射輝度スケール)?;
        Ok(Self {
            方向係数,
            放射輝度スケール,
            夜空放射輝度: 描画.夜空放射輝度(),
            昼係数: 状態.昼係数(),
            太陽円盤放射輝度: 描画.太陽円盤放射輝度(),
            太陽円盤角半径: 描画.太陽円盤角半径(),
        })
    }

    pub fn 方向係数(&self) -> [[f32; hosek_wilkie::チャネル数]; hosek_wilkie::係数数] {
        self.方向係数
    }

    pub fn 放射輝度スケール(&self) -> [f32; hosek_wilkie::チャネル数] {
        self.放射輝度スケール
    }

    pub fn 夜空放射輝度(&self) -> 放射輝度色 {
        self.夜空放射輝度
    }

    pub fn 昼係数(&self) -> 昼係数 {
        self.昼係数
    }

    pub fn 太陽円盤放射輝度(&self) -> 放射輝度色 {
        self.太陽円盤放射輝度
    }

    pub fn 太陽円盤角半径(&self) -> ラジアン {
        self.太陽円盤角半径
    }
}

/// 天頂角から高度へ戻し、定義域の下端(地平線)で頭打ちにする。
fn 定義域内の太陽高度(太陽天頂角: ラジアン) -> f32 {
    (std::f32::consts::FRAC_PI_2 - 太陽天頂角.値()).clamp(0.0, std::f32::consts::FRAC_PI_2)
}

fn 有限性を確かめる(
    方向係数: &[[f32; hosek_wilkie::チャネル数]; hosek_wilkie::係数数],
    放射輝度スケール: &[f32; hosek_wilkie::チャネル数],
) -> Result<(), 天空状態エラー> {
    for 値 in 方向係数.iter().flatten().chain(放射輝度スケール.iter()) {
        if !値.is_finite() {
            return Err(天空状態エラー::値域外("空放射輝度係数", *値));
        }
    }
    Ok(())
}
