//! 太陽の天頂余弦の値域[-1, +1]を一様に分けた半開区間と、その所属の決め方。
//!
//! 所属を整数の区間識別で決めるのは、下端の値と幅の反復加算で境界を作ると、単精度の丸めで境界近傍の所属が
//! 実行のたびに往復する余地が残るためである。ここは整数どうしの比較だけで所属を決め、
//! 浮動小数から整数への変換を1度も通らない(`as`キャストは規約で禁止であり、探索で代える)。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」

use super::{代表天頂余弦, 天空状態エラー, 間引きの刻みの設定};

/// 区間は下端を含み上端を含まない。値域の上端である+1はいちばん上の区間へ入る。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 太陽天頂区間 {
    区間識別: u16,
    設定: 間引きの刻みの設定,
}

impl 太陽天頂区間 {
    /// 天頂余弦が属する区間を返す。非有限の入力は型付きの失敗にする。
    ///
    /// 値域をわずかに外れた入力を両端へ寄せるのは、この値が単位ベクトルの天頂成分であり、正規化の丸めで
    /// -1や+1をごくわずかに超えうるためである。寄せずに扱うと区間識別が値域の外へ出る。
    pub fn 属する区間(天頂余弦: f32, 設定: 間引きの刻みの設定) -> Result<Self, 天空状態エラー> {
        if !天頂余弦.is_finite() {
            return Err(天空状態エラー::値域外("太陽天頂余弦", 天頂余弦));
        }
        let 区間の数 = 設定.区間の数().get();
        let 位置 = (f64::from(天頂余弦.clamp(-1.0, 1.0)) + 1.0) * f64::from(区間の数) / 2.0;
        Ok(Self {
            区間識別: 識別を探す(位置, 区間の数),
            設定,
        })
    }

    /// 区間を表す整数。境界の取り違えを整数のまま検査できるよう診断へ出す。
    pub fn 区間識別(self) -> u16 {
        self.区間識別
    }

    /// 区間の中央の天頂余弦。区間の下端に幅の半分を足すのでなく、識別から1つの式で求めるのは、
    /// 同じ識別からは常に同じ値が出ることを加算の順に依存させないためである。
    pub fn 代表天頂余弦(self) -> 代表天頂余弦 {
        let 区間の数 = f32::from(self.設定.区間の数().get());
        代表天頂余弦::生成する((2.0 * f32::from(self.区間識別) + 1.0) / 区間の数 - 1.0)
    }
}

/// 値域を区間の数へ引き伸ばした位置が入る区間の識別。`識別 <= 位置`を満たす最大の識別を二分探索で選ぶ。
/// 位置は0以上かつ区間の数以下であるため、答えは0から区間の数-1までに収まる。
fn 識別を探す(位置: f64, 区間の数: u16) -> u16 {
    let mut 下 = 0;
    let mut 上 = 区間の数 - 1;
    while 下 < 上 {
        let 中 = 下 + (上 - 下).div_ceil(2);
        if f64::from(中) <= 位置 {
            下 = 中;
        } else {
            上 = 中 - 1;
        }
    }
    下
}
