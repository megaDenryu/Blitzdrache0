//! 太陽の日周運動を決める設定。時刻だけでは決まらない値をシーンが持つ。

use blitz_math::ラジアン;

use super::天空状態エラー;
use crate::time::一日の長さ;

/// 既定の観測地の緯度。北緯35度は日本の本州中央部に相当する。
const 既定の緯度の度: f32 = 35.0;
/// 既定の太陽赤緯。季節はこの段のスコープ外であるため、春分・秋分と同じ0度で固定する。
const 既定の太陽赤緯の度: f32 = 0.0;

/// 観測地の緯度・太陽赤緯・一日の長さ。太陽方向はこの3つと一日内時刻だけで決まる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 天球方針 {
    緯度: ラジアン,
    太陽赤緯: ラジアン,
    一日の長さ: 一日の長さ,
}

impl 天球方針 {
    pub fn 生成する(緯度: ラジアン, 太陽赤緯: ラジアン, 一日の長さ: 一日の長さ) -> Result<Self, 天空状態エラー> {
        let 直角 = std::f32::consts::FRAC_PI_2;
        for (項目, 角) in [("緯度", 緯度), ("太陽赤緯", 太陽赤緯)] {
            if !角.値().is_finite() || 角.値().abs() > 直角 {
                return Err(天空状態エラー::値域外(項目, 角.値()));
            }
        }
        Ok(Self {
            緯度, 太陽赤緯, 一日の長さ
        })
    }

    pub fn 既定値() -> Self {
        Self {
            緯度: ラジアン::度から(既定の緯度の度),
            太陽赤緯: ラジアン::度から(既定の太陽赤緯の度),
            一日の長さ: 一日の長さ::地球の一日(),
        }
    }

    pub fn 緯度(&self) -> ラジアン {
        self.緯度
    }

    pub fn 太陽赤緯(&self) -> ラジアン {
        self.太陽赤緯
    }

    pub fn 一日の長さ(&self) -> 一日の長さ {
        self.一日の長さ
    }
}
