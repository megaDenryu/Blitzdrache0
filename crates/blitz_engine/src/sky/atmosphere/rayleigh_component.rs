//! 空気分子による散乱の成分。空が青く、地平線近くが赤いことの主因である。

use blitz_math::メートル;

use super::{密度分布, 消散係数RGB};
use crate::sky::天空状態エラー;

/// 地表での散乱係数(毎メートル)。波長の4乗に反比例するため青が最も強い。
/// 参照: Sebastien Hillaire, "A Scalable and Production Ready Sky and Atmosphere Rendering Technique" (EGSR 2020)の地球パラメータ。
const 地球の散乱係数の毎メートル: [f32; 3] = [5.802e-6, 13.558e-6, 33.100e-6];
/// 空気分子の密度が1/eへ減るまでの高さ。同上の出典による。
const 地球の尺度高度のメートル: f32 = 8000.0;

/// 空気分子の散乱係数と、その密度が高さ方向にどう減るかを決める尺度高度。
/// 空気分子は可視光をほとんど吸収しないため、消散係数は散乱係数と等しいものとして扱う。
/// 不変条件: 尺度高度は有限かつ正である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct レイリー成分 {
    散乱係数: 消散係数RGB,
    尺度高度: メートル,
}

impl レイリー成分 {
    pub fn 生成する(散乱係数: 消散係数RGB, 尺度高度: メートル) -> Result<Self, 天空状態エラー> {
        密度分布::指数分布(尺度高度)?;
        Ok(Self { 散乱係数, 尺度高度 })
    }

    pub fn 地球標準() -> Self {
        let [赤, 緑, 青] = 地球の散乱係数の毎メートル;
        Self {
            散乱係数: 消散係数RGB::検証済みの毎メートルから(赤, 緑, 青),
            尺度高度: メートル::生成する(地球の尺度高度のメートル),
        }
    }

    pub fn 散乱係数(&self) -> 消散係数RGB {
        self.散乱係数
    }

    /// 吸収を持たないため、消散係数は散乱係数そのものである。
    pub fn 消散係数(&self) -> 消散係数RGB {
        self.散乱係数
    }

    pub fn 尺度高度(&self) -> メートル {
        self.尺度高度
    }

    /// 尺度高度が正であることは生成で検証済みであるため、指数分布の導出はここでは失敗しえない。
    pub fn 密度分布(&self) -> 密度分布 {
        密度分布::検証済みの指数分布(self.尺度高度)
    }
}
