//! 特定の高度帯に偏って光を吸収する層の成分。地球ではオゾンがこれにあたり、薄明の空の青紫を作る。

use blitz_math::メートル;

use super::{密度分布, 消散係数RGB};

/// オゾンの消散係数(毎メートル)。緑の波長を最も強く吸収する。
/// 参照: Sebastien Hillaire, "A Scalable and Production Ready Sky and Atmosphere Rendering Technique" (EGSR 2020)の地球パラメータ。
const 地球の消散係数の毎メートル: [f32; 3] = [0.650e-6, 1.881e-6, 0.085e-6];
/// オゾン層の折れ線分布の3つの高度。10kmで立ち上がり25kmで最大、40kmで再び0になる。同上の出典による。
const 地球の下端高度のメートル: f32 = 10_000.0;
const 地球の頂点高度のメートル: f32 = 25_000.0;
const 地球の上端高度のメートル: f32 = 40_000.0;

/// 散乱を伴わず吸収だけを行う層の消散係数と、その密度分布。
/// 散乱係数を持たないのは、この層が視線へ光を足さず減らすだけであり、散乱の相手として位相関数を要さないためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 吸収成分 {
    消散係数: 消散係数RGB,
    密度分布: 密度分布,
}

impl 吸収成分 {
    /// 消散係数も密度分布も自身の生成で不変条件を検証済みであるため、束ねる操作は失敗しない。
    pub fn 生成する(消散係数: 消散係数RGB, 密度分布: 密度分布) -> Self {
        Self { 消散係数, 密度分布 }
    }

    pub fn 地球標準() -> Self {
        let [赤, 緑, 青] = 地球の消散係数の毎メートル;
        Self {
            消散係数: 消散係数RGB::検証済みの毎メートルから(赤, 緑, 青),
            密度分布: 密度分布::検証済みのテント(
                メートル::生成する(地球の下端高度のメートル),
                メートル::生成する(地球の頂点高度のメートル),
                メートル::生成する(地球の上端高度のメートル),
            ),
        }
    }

    pub fn 消散係数(&self) -> 消散係数RGB {
        self.消散係数
    }

    pub fn 密度分布(&self) -> 密度分布 {
        self.密度分布
    }
}
