//! 大気の値を固定順の正規化ビット列へ書き出し、その要約を作る工程。受け取るのは単位付きの値、返すのはビット列と64ビットの要約である。
//!
//! 浮動小数を`==`でなくビット表現で取り込むのは、正のゼロと負のゼロが`==`では等しいのに別々の値であり、
//! 値の比較で更新判定を行う契約が「同じ鍵なら同じ大気」の向きで破れるためである。値の有限性は各値オブジェクトの
//! 生成が保証しており、NaNの複数表現がここへ届くことはない。
//!
//! 要約にFNV-1aを自前で書くのは、標準ライブラリの`DefaultHasher`が版をまたいだ出力の同一性を約束していないためである。
//! 大気静的キーはLUTを作り直すかどうかの判定に使い、同じ大気からは常に同じ鍵が出ることを契約とするため、
//! ハッシュ関数の実装がコンパイラの版で変わることを許せない。

use blitz_math::{メートル, 逆メートル};

/// 大気媒体方針が持つ数値の個数。惑星形状2・レイリー4・ミー8・吸収13・地表アルベド3の合計である。
/// 方針へ値を足したときにここを直し忘れると、`完成する`が取り込んだ個数の食い違いとして止める。
pub(super) const 大気パラメータ数: usize = 30;

const FNVの初期値: u64 = 0xcbf2_9ce4_8422_2325;
const FNVの乗数: u64 = 0x0000_0100_0000_01b3;

/// 値をひとつずつ固定の順序で取り込む器。
pub(super) struct キー畳み込み {
    ビット列: [u32; 大気パラメータ数],
    取り込んだ個数: usize,
}

impl キー畳み込み {
    pub(super) fn 新規() -> Self {
        Self {
            ビット列: [0; 大気パラメータ数],
            取り込んだ個数: 0,
        }
    }

    pub(super) fn 実数(&mut self, 値: f32) -> &mut Self {
        let Some(枠) = self.ビット列.get_mut(self.取り込んだ個数) else {
            panic!("大気パラメータ数{大気パラメータ数}を超えて値を取り込んだ。方針へ足した値の分だけこの定数を増やすこと");
        };
        *枠 = 値.to_bits();
        self.取り込んだ個数 += 1;
        self
    }

    pub(super) fn 長さ(&mut self, 長さ: メートル) -> &mut Self {
        self.実数(長さ.値())
    }

    pub(super) fn 逆長さ(&mut self, 逆長さ: 逆メートル) -> &mut Self {
        self.実数(逆長さ.値())
    }

    pub(super) fn 三成分(&mut self, 成分: [f32; 3]) -> &mut Self {
        for 値 in 成分 {
            self.実数(値);
        }
        self
    }

    /// 取り込みを終えたビット列と、その要約を返す。
    /// 要約をビット列だけから導くのは、「要約が違えばビット列も必ず違う」という関係を構造で保つためである。
    /// この関係が無いと、要約を先に見る等値判定が本来等しくない鍵を等しいと答えうる。
    pub(super) fn 完成する(&self) -> ([u32; 大気パラメータ数], u64) {
        assert_eq!(
            self.取り込んだ個数, 大気パラメータ数,
            "大気パラメータ数と取り込んだ値の個数が違う。方針の値と取り込みの並びが食い違っている"
        );
        (self.ビット列, 要約する(&self.ビット列))
    }
}

fn 要約する(ビット列: &[u32; 大気パラメータ数]) -> u64 {
    let mut 要約 = FNVの初期値;
    for 値 in ビット列 {
        for バイト in 値.to_le_bytes() {
            要約 = (要約 ^ u64::from(バイト)).wrapping_mul(FNVの乗数);
        }
    }
    要約
}
