//! 高度の1区間について密度の高さ方向の形を決める係数の組。

use blitz_math::{メートル, 逆メートル};

use crate::sky::天空状態エラー;

/// 高度hにおける規格化密度を`指数項 * exp(指数尺度 * h) + 線形項 * h + 定数項`として与え、0以上1以下へ切り詰める層。
/// 指数分布も線形のテント関数も同じ4つの係数で表せるため、成分ごとに別の式を持たずに済む。
/// `幅`はこの層が担当する高度の上限であり、大気上端まで伸びる最後の層では読まれない。
/// 不変条件: 5つの係数はすべて有限であり、幅は0以上である。
/// 参照: Eric Bruneton, "Precomputed Atmospheric Scattering" (2017改訂実装)の`DensityProfileLayer`。同じ係数の並びを採る。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 密度分布層 {
    幅: メートル,
    指数項: f32,
    指数尺度: 逆メートル,
    線形項: 逆メートル,
    定数項: f32,
}

impl 密度分布層 {
    pub fn 生成する(
        幅: メートル, 指数項: f32, 指数尺度: 逆メートル, 線形項: 逆メートル, 定数項: f32
    ) -> Result<Self, 天空状態エラー> {
        let 検査対象 = [
            ("幅", 幅.値()),
            ("指数項", 指数項),
            ("指数尺度", 指数尺度.値()),
            ("線形項", 線形項.値()),
            ("定数項", 定数項),
        ];
        for (項目, 値) in 検査対象 {
            if !値.is_finite() {
                return Err(天空状態エラー::値域外(項目, 値));
            }
        }
        if 幅.値() < 0.0 {
            return Err(天空状態エラー::値域外("幅", 幅.値()));
        }
        Ok(Self {
            幅,
            指数項,
            指数尺度,
            線形項,
            定数項,
        })
    }

    /// 5つの係数が有限であることを呼び出し側の不変条件が保証しているときの入口。
    /// 前提: 5つの係数はすべて有限であり、幅は0以上である。
    pub(super) fn 検証済みで組む(
        幅: メートル, 指数項: f32, 指数尺度: 逆メートル, 線形項: 逆メートル, 定数項: f32
    ) -> Self {
        Self {
            幅,
            指数項,
            指数尺度,
            線形項,
            定数項,
        }
    }

    /// どの高度でも密度0になる層。テント関数の下側のように、担当区間の外を明示的に空にするために使う。
    pub fn 空() -> Self {
        Self {
            幅: メートル::生成する(0.0),
            指数項: 0.0,
            指数尺度: 逆メートル::生成する(0.0),
            線形項: 逆メートル::生成する(0.0),
            定数項: 0.0,
        }
    }

    pub fn 幅(&self) -> メートル {
        self.幅
    }

    pub fn 指数項(&self) -> f32 {
        self.指数項
    }

    pub fn 指数尺度(&self) -> 逆メートル {
        self.指数尺度
    }

    pub fn 線形項(&self) -> 逆メートル {
        self.線形項
    }

    pub fn 定数項(&self) -> f32 {
        self.定数項
    }
}
