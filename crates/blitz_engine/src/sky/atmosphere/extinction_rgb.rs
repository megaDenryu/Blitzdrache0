//! 単位長さあたりに光が失われる割合を、赤・緑・青の3成分で表した係数。

use blitz_math::逆メートル;

use crate::sky::天空状態エラー;

/// 散乱係数・吸収係数・消散係数に共通の型。どれも次元は逆長さであり、意味の違いは保持する側の名前が表す。
/// 不変条件: 3成分とも有限かつ0以上である。負の係数は光を進むほど増やす向きになり、物理的にも描画的にも意味を持たない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 消散係数RGB {
    成分: [逆メートル; 3],
}

impl 消散係数RGB {
    pub fn 生成する(赤: 逆メートル, 緑: 逆メートル, 青: 逆メートル) -> Result<Self, 天空状態エラー> {
        let 成分 = [赤, 緑, 青];
        for 値 in 成分 {
            if !値.値().is_finite() || 値.値() < 0.0 {
                return Err(天空状態エラー::値域外("消散係数RGB", 値.値()));
            }
        }
        Ok(Self { 成分 })
    }

    /// 毎メートル単位の3つの生値から作る。文献値がこの単位で表になっているため、変換の手間を境界1箇所へ閉じる。
    pub fn 毎メートルから(赤: f32, 緑: f32, 青: f32) -> Result<Self, 天空状態エラー> {
        Self::生成する(逆メートル::生成する(赤), 逆メートル::生成する(緑), 逆メートル::生成する(青))
    }

    /// 検証を通らない値では組み立てられないため、既定値の構築だけがこの入口を使う。
    pub(super) fn 検証済みの毎メートルから(赤: f32, 緑: f32, 青: f32) -> Self {
        Self {
            成分: [逆メートル::生成する(赤), 逆メートル::生成する(緑), 逆メートル::生成する(青)],
        }
    }

    pub fn 成分(&self) -> [逆メートル; 3] {
        self.成分
    }

    /// 散乱と吸収を足して消散を作る。0以上どうしの和は0以上のままであるため、この操作は不変条件を破らない。
    pub fn 加える(&self, 他: &Self) -> Self {
        Self {
            成分: [self.成分[0] + 他.成分[0], self.成分[1] + 他.成分[1], self.成分[2] + 他.成分[2]],
        }
    }
}
