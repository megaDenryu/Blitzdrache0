//! 高度から規格化密度への対応を、下から順に重ねた2つの層で表したもの。

use blitz_math::{メートル, 逆メートル};

use super::密度分布層;
use crate::sky::天空状態エラー;

/// 高度が第1層の幅より小さければ第1層、そうでなければ第2層の式で密度を決める分布。
/// 層を2つに固定するのは、大気の各成分がとる形が「指数分布」と「高度に対して折れ線のテント関数」の2つに尽きるためである。
/// 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「大気LUT方式の設計(第7段で実装する)」
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 密度分布 {
    層: [密度分布層; 2],
}

impl 密度分布 {
    pub fn 生成する(第1層: 密度分布層, 第2層: 密度分布層) -> Self {
        Self { 層: [第1層, 第2層] }
    }

    /// 地表で1、上へ向かって尺度高度ごとに1/eへ減る指数分布。分子と粒子の密度がこの形をとる。
    /// 第1層の幅を0にすることで、全高度が第2層の式で決まる。
    pub fn 指数分布(尺度高度: メートル) -> Result<Self, 天空状態エラー> {
        if !尺度高度.値().is_finite() || 尺度高度.値() <= 0.0 {
            return Err(天空状態エラー::値域外("尺度高度", 尺度高度.値()));
        }
        Ok(Self::検証済みの指数分布(尺度高度))
    }

    /// 尺度高度が有限かつ正であることを呼び出し側の不変条件が保証しているときの入口。
    /// 前提: 尺度高度は有限かつ正である。破ると減衰率が無限大または符号の逆転した値になる。
    pub(super) fn 検証済みの指数分布(尺度高度: メートル) -> Self {
        let 減衰 = 逆メートル::生成する(-逆メートル::長さの逆数(尺度高度).値());
        let 第2層 = 密度分布層::検証済みで組む(メートル::生成する(0.0), 1.0, 減衰, 逆メートル::生成する(0.0), 0.0);
        Self::生成する(密度分布層::空(), 第2層)
    }

    /// 下端高度で0、頂点高度で1、上端高度で再び0になる折れ線。オゾンのように特定の高度帯に偏る吸収層がこの形をとる。
    /// 区間の外は層の式が負の値を返し、規格化密度の切り詰めで0になる。
    pub fn テント(下端高度: メートル, 頂点高度: メートル, 上端高度: メートル) -> Result<Self, 天空状態エラー> {
        let 高度一覧 = [("下端高度", 下端高度), ("頂点高度", 頂点高度), ("上端高度", 上端高度)];
        for (項目, 高度) in 高度一覧 {
            if !高度.値().is_finite() || 高度.値() < 0.0 {
                return Err(天空状態エラー::値域外(項目, 高度.値()));
            }
        }
        if 下端高度 >= 頂点高度 || 頂点高度 >= 上端高度 {
            return Err(天空状態エラー::値域外("頂点高度", 頂点高度.値()));
        }
        Ok(Self::検証済みのテント(下端高度, 頂点高度, 上端高度))
    }

    /// 3つの高度が有限かつ狭義単調増加であることを呼び出し側の不変条件が保証しているときの入口。
    /// 前提: 下端高度 < 頂点高度 < 上端高度 であり、いずれも有限かつ0以上である。破ると折れ線の傾きが無限大になる。
    pub(super) fn 検証済みのテント(下端高度: メートル, 頂点高度: メートル, 上端高度: メートル) -> Self {
        let 上り幅 = (頂点高度 - 下端高度).値();
        let 下り幅 = (上端高度 - 頂点高度).値();
        let 零 = 逆メートル::生成する(0.0);
        let 上り = 密度分布層::検証済みで組む(頂点高度, 0.0, 零, 逆メートル::生成する(1.0 / 上り幅), -下端高度.値() / 上り幅);
        let 下り = 密度分布層::検証済みで組む(
            メートル::生成する(0.0),
            0.0,
            零,
            逆メートル::生成する(-1.0 / 下り幅),
            上端高度.値() / 下り幅,
        );
        Self::生成する(上り, 下り)
    }

    pub fn 層(&self) -> [密度分布層; 2] {
        self.層
    }
}
