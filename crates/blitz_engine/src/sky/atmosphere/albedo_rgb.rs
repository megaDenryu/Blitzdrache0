//! 地表が入射光を跳ね返す割合を、赤・緑・青の3成分で表した反射率。

use crate::sky::天空状態エラー;

/// 地球の代表値として使う反射率。Bruneton 2017実装のデモが全波長で採る0.1に合わせる。
/// 0にすると地面からの照り返しが完全に消えて多重散乱の検証条件として退化するため、正の値を既定に置く。
/// 参照: Eric Bruneton, "Precomputed Atmospheric Scattering" (2017改訂実装)のデモの`kGroundAlbedo`。
const 地球の反射率: f32 = 0.1;

/// 大気の下端で光を反射する地面の反射率。多重散乱の計算が地面からの照り返しを取り込むときの入力になる。
/// 不変条件: 3成分とも有限かつ0以上1以下である。1を超える反射率は入射より多くの光を返し、多重散乱の反復が発散する。
/// Hosek-Wilkie解析近似が使う単一成分の`地表アルベド`とは別の型にする。前者は解析近似の定義域に縛られた1つの数であり、
/// こちらは波長ごとに異なる地面の色を表せなければならないためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 地表アルベドRGB {
    成分: [f32; 3],
}

impl 地表アルベドRGB {
    pub fn 生成する(赤: f32, 緑: f32, 青: f32) -> Result<Self, 天空状態エラー> {
        let 成分 = [赤, 緑, 青];
        for 値 in 成分 {
            if !値.is_finite() || !(0.0..=1.0).contains(&値) {
                return Err(天空状態エラー::値域外("地表アルベドRGB", 値));
            }
        }
        Ok(Self { 成分 })
    }

    pub fn 地球標準() -> Self {
        Self {
            成分: [地球の反射率; 3]
        }
    }

    pub fn 成分(&self) -> [f32; 3] {
        self.成分
    }
}
