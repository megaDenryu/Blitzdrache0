//! 塵や水滴といった浮遊粒子(エアロゾル)による散乱と吸収の成分。太陽の周りの白い暈と、霞んだ遠景を作る。

use blitz_math::メートル;

use super::{位相非対称係数, 密度分布, 消散係数RGB};
use crate::sky::天空状態エラー;

/// 地表での散乱係数(毎メートル)。粒子は空気分子より大きく、波長への依存がほとんど無いため3成分が等しい。
/// 参照: Sebastien Hillaire, "A Scalable and Production Ready Sky and Atmosphere Rendering Technique" (EGSR 2020)の地球パラメータ。
const 地球の散乱係数の毎メートル: f32 = 3.996e-6;
/// 同出典の消散係数4.440e-6から散乱係数を引いた吸収の分。
const 地球の吸収係数の毎メートル: f32 = 0.444e-6;
/// 浮遊粒子の密度が1/eへ減るまでの高さ。同上の出典による。
const 地球の尺度高度のメートル: f32 = 1200.0;
/// 前方散乱への偏り。同上の出典による。
const 地球の位相非対称係数: f32 = 0.8;

/// 浮遊粒子の散乱係数・吸収係数・尺度高度・位相の偏り。
/// 消散係数を独立の値として持たず散乱と吸収の和として導くのは、3つを別々に保持すると
/// 「消散は散乱と吸収の和である」という関係が破れた値の組を表現できてしまうためである。
/// 不変条件: 尺度高度は有限かつ正である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ミー成分 {
    散乱係数: 消散係数RGB,
    吸収係数: 消散係数RGB,
    尺度高度: メートル,
    位相非対称係数: 位相非対称係数,
}

impl ミー成分 {
    pub fn 生成する(
        散乱係数: 消散係数RGB,
        吸収係数: 消散係数RGB,
        尺度高度: メートル,
        位相非対称係数: 位相非対称係数,
    ) -> Result<Self, 天空状態エラー> {
        密度分布::指数分布(尺度高度)?;
        Ok(Self {
            散乱係数,
            吸収係数,
            尺度高度,
            位相非対称係数,
        })
    }

    pub fn 地球標準() -> Self {
        let 散乱 = 地球の散乱係数の毎メートル;
        let 吸収 = 地球の吸収係数の毎メートル;
        Self {
            散乱係数: 消散係数RGB::検証済みの毎メートルから(散乱, 散乱, 散乱),
            吸収係数: 消散係数RGB::検証済みの毎メートルから(吸収, 吸収, 吸収),
            尺度高度: メートル::生成する(地球の尺度高度のメートル),
            位相非対称係数: 位相非対称係数::検証済みの値から(地球の位相非対称係数),
        }
    }

    pub fn 散乱係数(&self) -> 消散係数RGB {
        self.散乱係数
    }

    pub fn 吸収係数(&self) -> 消散係数RGB {
        self.吸収係数
    }

    pub fn 消散係数(&self) -> 消散係数RGB {
        self.散乱係数.加える(&self.吸収係数)
    }

    pub fn 尺度高度(&self) -> メートル {
        self.尺度高度
    }

    pub fn 位相非対称係数(&self) -> 位相非対称係数 {
        self.位相非対称係数
    }

    /// 尺度高度が正であることは生成で検証済みであるため、指数分布の導出はここでは失敗しえない。
    pub fn 密度分布(&self) -> 密度分布 {
        密度分布::検証済みの指数分布(self.尺度高度)
    }
}
