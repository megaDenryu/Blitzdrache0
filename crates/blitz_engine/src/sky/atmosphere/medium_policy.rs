//! 大気媒体方針。その世界の大気が何でできているかを、時刻に依存しない形で1つに束ねた方針。

use super::{ミー成分, レイリー成分, 吸収成分, 地表アルベドRGB, 大気静的キー, 惑星形状};

/// 惑星の形・空気分子・浮遊粒子・吸収層・地表の反射率からなる、大気の物理パラメータ一式。
/// 太陽の角半径と放射照度をここへ入れないのは、それらが大気そのものの性質ではなく天体側の性質であり、
/// 大気が変わらないまま太陽だけが変わる場合に透過率と多重散乱のベイク済み画像を作り直す必要が無いためである。
/// 同じ方針からは常に同じ大気静的キーが得られる(決定性)。
/// 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「大気のベイク済み画像方式の設計(第7段で実装する)」
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 大気媒体方針 {
    惑星形状: 惑星形状,
    レイリー: レイリー成分,
    ミー: ミー成分,
    吸収: 吸収成分,
    地表アルベド: 地表アルベドRGB,
}

impl 大気媒体方針 {
    /// 各成分は自身の生成で値域を検証済みであるため、束ねる操作は失敗しない。
    pub fn 生成する(
        惑星形状: 惑星形状, レイリー: レイリー成分, ミー: ミー成分, 吸収: 吸収成分, 地表アルベド: 地表アルベドRGB
    ) -> Self {
        Self {
            惑星形状,
            レイリー,
            ミー,
            吸収,
            地表アルベド,
        }
    }

    /// 地球の標準的な大気。各数値の出典は成分ごとの型の定義箇所にある。
    pub fn 地球標準() -> Self {
        Self {
            惑星形状: 惑星形状::地球標準(),
            レイリー: レイリー成分::地球標準(),
            ミー: ミー成分::地球標準(),
            吸収: 吸収成分::地球標準(),
            地表アルベド: 地表アルベドRGB::地球標準(),
        }
    }

    pub fn 惑星形状(&self) -> 惑星形状 {
        self.惑星形状
    }

    pub fn レイリー(&self) -> レイリー成分 {
        self.レイリー
    }

    pub fn ミー(&self) -> ミー成分 {
        self.ミー
    }

    pub fn 吸収(&self) -> 吸収成分 {
        self.吸収
    }

    pub fn 地表アルベド(&self) -> 地表アルベドRGB {
        self.地表アルベド
    }

    /// 透過率のベイク済み画像と多重散乱のベイク済み画像を作り直すかどうかを値の比較で決めるための鍵。
    pub fn 静的キー(&self) -> 大気静的キー {
        大気静的キー::方針から導く(self)
    }
}
