//! 大気媒体方針から決まる更新判定の鍵。透過率のベイク済み画像と多重散乱のベイク済み画像を作り直すかどうかをこの値の比較で決める。

use super::key_digest::{キー畳み込み, 大気パラメータ数};
use super::{大気媒体方針, 密度分布, 消散係数RGB};

/// 大気媒体方針の全パラメータを固定の順序で並べた正規化ビット列と、その64ビットの要約。
/// 要約だけでなくビット列そのものを持って等値を判定するのは、64ビットへ畳んだ値には異なる大気が同じ値へ写る衝突が
/// 原理的に存在し、衝突すると方針を変えたのに古いベイク済み画像を参照し続けるという、絵にしか現れない欠陥になるためである。
/// 可変なdirty通知でなくこの値の比較で更新を決めるのは、通知の付け忘れが同じ欠陥を生むのに対し、値比較は
/// 方針が変わった事実そのものから判定できるためである。
/// 注意: 要約をビット列より先に置くのは、宣言順に比べる導出済みの等値実装が、まず要約の不一致で抜けるようにするためである。
/// 要約はビット列だけから導くため、この順序は判定の結果を変えない。
/// 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「大気のベイク済み画像方式の設計(第7段で実装する)」
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct 大気静的キー {
    要約: u64,
    ビット列: [u32; 大気パラメータ数],
}

impl 大気静的キー {
    pub(super) fn 方針から導く(方針: &大気媒体方針) -> Self {
        let mut 畳み込み = キー畳み込み::新規();
        畳み込み.長さ(方針.惑星形状().下端半径()).長さ(方針.惑星形状().上端半径());
        係数を取り込む(&mut 畳み込み, 方針.レイリー().散乱係数());
        畳み込み.長さ(方針.レイリー().尺度高度());
        係数を取り込む(&mut 畳み込み, 方針.ミー().散乱係数());
        係数を取り込む(&mut 畳み込み, 方針.ミー().吸収係数());
        畳み込み.長さ(方針.ミー().尺度高度()).実数(方針.ミー().位相非対称係数().値());
        係数を取り込む(&mut 畳み込み, 方針.吸収().消散係数());
        分布を取り込む(&mut 畳み込み, 方針.吸収().密度分布());
        畳み込み.三成分(方針.地表アルベド().成分());
        let (ビット列, 要約) = 畳み込み.完成する();
        Self { 要約, ビット列 }
    }

    /// 記録や表示のための短い要約。異なる大気が同じ要約を持ちうるため、これで等しさを判定してはならない。
    /// 鍵が等しいかどうかは`==`で見る。
    pub fn 要約値(&self) -> u64 {
        self.要約
    }
}

fn 係数を取り込む(畳み込み: &mut キー畳み込み, 係数: 消散係数RGB) {
    for 成分 in 係数.成分() {
        畳み込み.逆長さ(成分);
    }
}

fn 分布を取り込む(畳み込み: &mut キー畳み込み, 分布: 密度分布) {
    for 層 in 分布.層() {
        畳み込み.長さ(層.幅()).実数(層.指数項());
        畳み込み.逆長さ(層.指数尺度()).逆長さ(層.線形項()).実数(層.定数項());
    }
}
