//! 地球標準から1つのパラメータだけを替えた方針を作る工程。受け取るのは書き込み先の一覧、書き込むのは名前と方針の組である。
//! 鍵が方針のどの値も取りこぼしていないことは、この一覧の全件が地球標準と違う鍵になることで確かめる。

use super::component_variants::{係数の1成分をずらす, 分布の1係数をずらす, 割合のずれ, 長さをずらす};
use crate::sky::atmosphere::{
    ミー成分, レイリー成分, 位相非対称係数, 吸収成分, 地表反射率RGB, 大気媒体方針, 惑星形状
};

type 方針一覧 = Vec<(String, 大気媒体方針)>;

pub(super) fn 一つだけ替えた方針一覧() -> 方針一覧 {
    let mut 一覧 = Vec::new();
    惑星形状の変形(&mut 一覧);
    レイリーの変形(&mut 一覧);
    ミーの変形(&mut 一覧);
    吸収の変形(&mut 一覧);
    地表反射率の変形(&mut 一覧);
    一覧
}

fn 惑星形状の変形(一覧: &mut 方針一覧) {
    let 基 = 大気媒体方針::地球標準();
    let 元 = 基.惑星形状();
    let 方針 = |形状| 大気媒体方針::生成する(形状, 基.レイリー(), 基.ミー(), 基.吸収(), 基.地表反射率());
    let 下端 = 惑星形状::生成する(長さをずらす(元.下端半径()), 元.上端半径()).unwrap();
    一覧.push(("惑星下端半径".to_string(), 方針(下端)));
    let 上端 = 惑星形状::生成する(元.下端半径(), 長さをずらす(元.上端半径())).unwrap();
    一覧.push(("大気上端半径".to_string(), 方針(上端)));
}

fn レイリーの変形(一覧: &mut 方針一覧) {
    let 基 = 大気媒体方針::地球標準();
    let 元 = 基.レイリー();
    let 方針 = |レイリー| 大気媒体方針::生成する(基.惑星形状(), レイリー, 基.ミー(), 基.吸収(), 基.地表反射率());
    for 添字 in 0..3 {
        let 係数 = 係数の1成分をずらす(元.散乱係数(), 添字);
        let 成分 = レイリー成分::生成する(係数, 元.尺度高度()).unwrap();
        一覧.push((format!("レイリー散乱係数{添字}"), 方針(成分)));
    }
    let 成分 = レイリー成分::生成する(元.散乱係数(), 長さをずらす(元.尺度高度())).unwrap();
    一覧.push(("レイリー尺度高度".to_string(), 方針(成分)));
}

fn ミーの変形(一覧: &mut 方針一覧) {
    let 基 = 大気媒体方針::地球標準();
    let 元 = 基.ミー();
    let 方針 = |ミー| 大気媒体方針::生成する(基.惑星形状(), 基.レイリー(), ミー, 基.吸収(), 基.地表反射率());
    let 組む = |散乱, 吸収, 尺度高度, 非対称| ミー成分::生成する(散乱, 吸収, 尺度高度, 非対称).unwrap();
    for 添字 in 0..3 {
        let 散乱係数 = 係数の1成分をずらす(元.散乱係数(), 添字);
        let 散乱 = 組む(散乱係数, 元.吸収係数(), 元.尺度高度(), 元.位相非対称係数());
        一覧.push((format!("ミー散乱係数{添字}"), 方針(散乱)));
        let 吸収係数 = 係数の1成分をずらす(元.吸収係数(), 添字);
        let 吸収 = 組む(元.散乱係数(), 吸収係数, 元.尺度高度(), 元.位相非対称係数());
        一覧.push((format!("ミー吸収係数{添字}"), 方針(吸収)));
    }
    let 尺度 = 組む(元.散乱係数(), 元.吸収係数(), 長さをずらす(元.尺度高度()), 元.位相非対称係数());
    一覧.push(("ミー尺度高度".to_string(), 方針(尺度)));
    let 非対称 = 位相非対称係数::生成する(元.位相非対称係数().値() - 割合のずれ).unwrap();
    let 偏り = 組む(元.散乱係数(), 元.吸収係数(), 元.尺度高度(), 非対称);
    一覧.push(("ミー位相非対称係数".to_string(), 方針(偏り)));
}

fn 吸収の変形(一覧: &mut 方針一覧) {
    let 基 = 大気媒体方針::地球標準();
    let 元 = 基.吸収();
    let 方針 = |吸収| 大気媒体方針::生成する(基.惑星形状(), 基.レイリー(), 基.ミー(), 吸収, 基.地表反射率());
    for 添字 in 0..3 {
        let 係数 = 係数の1成分をずらす(元.消散係数(), 添字);
        一覧.push((format!("吸収消散係数{添字}"), 方針(吸収成分::生成する(係数, 元.密度分布()))));
    }
    for 層添字 in 0..2 {
        for 係数添字 in 0..5 {
            let 分布 = 分布の1係数をずらす(元.密度分布(), 層添字, 係数添字);
            let 名前 = format!("吸収密度分布の第{層添字}層の第{係数添字}係数");
            一覧.push((名前, 方針(吸収成分::生成する(元.消散係数(), 分布))));
        }
    }
}

fn 地表反射率の変形(一覧: &mut 方針一覧) {
    let 基 = 大気媒体方針::地球標準();
    let 元 = 基.地表反射率().成分();
    let 方針 = |反射率| 大気媒体方針::生成する(基.惑星形状(), 基.レイリー(), 基.ミー(), 基.吸収(), 反射率);
    for 添字 in 0..3 {
        let mut 成分 = 元;
        成分[添字] += 割合のずれ;
        let 反射率 = 地表反射率RGB::生成する(成分[0], 成分[1], 成分[2]).unwrap();
        一覧.push((format!("地表反射率{添字}"), 方針(反射率)));
    }
}
