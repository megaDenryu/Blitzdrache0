//! 各成分の不変条件の検査。既定値が自身の検証を通ること、値域外の入力を拒むこと、導出が定義どおりであることを見る。

use super::m;
use crate::sky::atmosphere::*;

/// 既定値は検証を迂回して組み立てるため、同じ値を検証付きの入口へ通しても受理されることを確かめる。
/// これが無いと、既定値だけが不変条件を破った状態でも誰も気づけない。
#[test]
fn 地球標準の各成分は自身の検証を通る() {
    let 形状 = 惑星形状::地球標準();
    assert_eq!(惑星形状::生成する(形状.下端半径(), 形状.上端半径()).unwrap(), 形状);
    let レイリー = レイリー成分::地球標準();
    assert_eq!(レイリー成分::生成する(レイリー.散乱係数(), レイリー.尺度高度()).unwrap(), レイリー);
    let ミー = ミー成分::地球標準();
    let 再生成 = ミー成分::生成する(ミー.散乱係数(), ミー.吸収係数(), ミー.尺度高度(), ミー.位相非対称係数()).unwrap();
    assert_eq!(再生成, ミー);
    let 吸収 = 吸収成分::地球標準();
    assert_eq!(吸収成分::生成する(吸収.消散係数(), 吸収.密度分布()), 吸収);
    let アルベド = 地表アルベドRGB::地球標準().成分();
    assert!(地表アルベドRGB::生成する(アルベド[0], アルベド[1], アルベド[2]).is_ok());
    for 成分 in レイリー.散乱係数().成分() {
        assert!(消散係数RGB::生成する(成分, 成分, 成分).is_ok());
    }
}

#[test]
fn 値域外の入力を拒む() {
    assert!(惑星形状::生成する(m(6_460_000.0), m(6_360_000.0)).is_err());
    assert!(惑星形状::生成する(m(-1.0), m(1.0)).is_err());
    assert!(消散係数RGB::毎メートルから(-1e-6, 0.0, 0.0).is_err());
    assert!(消散係数RGB::毎メートルから(f32::NAN, 0.0, 0.0).is_err());
    assert!(地表アルベドRGB::生成する(1.5, 0.0, 0.0).is_err());
    assert!(位相非対称係数::生成する(1.0).is_err());
    assert!(位相非対称係数::生成する(-1.0).is_err());
    assert!(位相非対称係数::生成する(0.9).is_ok());
    assert!(密度分布::指数分布(m(0.0)).is_err());
    assert!(密度分布::テント(m(25_000.0), m(10_000.0), m(40_000.0)).is_err());
}

/// 吸収層の折れ線が、下端で0・頂点で1・上端で0という設計どおりの係数へ展開されることを確かめる。
#[test]
fn テント分布の係数が3つの高度から決まる() {
    let 分布 = 密度分布::テント(m(10_000.0), m(25_000.0), m(40_000.0)).unwrap();
    let [上り, 下り] = 分布.層();
    assert_eq!(上り.幅(), m(25_000.0));
    assert!((上り.線形項().値() - 1.0 / 15_000.0).abs() < 1e-12);
    assert!((上り.定数項() + 2.0 / 3.0).abs() < 1e-6);
    assert!((下り.線形項().値() + 1.0 / 15_000.0).abs() < 1e-12);
    assert!((下り.定数項() - 8.0 / 3.0).abs() < 1e-6);
}

#[test]
fn ミーの消散係数は散乱と吸収の和になる() {
    let ミー = ミー成分::地球標準();
    for (添字, 消散) in ミー.消散係数().成分().iter().enumerate() {
        let 期待 = ミー.散乱係数().成分()[添字].値() + ミー.吸収係数().成分()[添字].値();
        assert!((消散.値() - 期待).abs() < 1e-12);
    }
}
