//! 大気静的キーの検査。同じ方針が同じ鍵へ写ること、パラメータの違いが鍵の違いへ出ることを見る。

use super::m;
use crate::sky::atmosphere::{レイリー成分, 大気媒体方針, 消散係数RGB};

fn 散乱係数を替えた方針(赤: f32, 緑: f32, 青: f32) -> 大気媒体方針 {
    let 方針 = 大気媒体方針::地球標準();
    let 係数 = 消散係数RGB::毎メートルから(赤, 緑, 青).unwrap();
    let レイリー = レイリー成分::生成する(係数, 方針.レイリー().尺度高度()).unwrap();
    大気媒体方針::生成する(方針.惑星形状(), レイリー, 方針.ミー(), 方針.吸収(), 方針.地表アルベド())
}

#[test]
fn 同じ方針は同じ鍵へ写る() {
    assert_eq!(大気媒体方針::地球標準().静的キー(), 大気媒体方針::地球標準().静的キー());
}

#[test]
fn 尺度高度の違いが鍵の違いへ出る() {
    let 方針 = 大気媒体方針::地球標準();
    let レイリー = レイリー成分::生成する(方針.レイリー().散乱係数(), m(8001.0)).unwrap();
    let 別の方針 = 大気媒体方針::生成する(方針.惑星形状(), レイリー, 方針.ミー(), 方針.吸収(), 方針.地表アルベド());
    assert_ne!(方針.静的キー(), 別の方針.静的キー());
}

/// 正のゼロと負のゼロは`==`では等しいが別々の値であるため、ビット表現で畳み込む鍵は両者を区別する。
/// 値の比較で更新を決める契約は「鍵が同じなら大気も同じ」の向きで守られている必要がある。
#[test]
fn 正のゼロと負のゼロを鍵が区別する() {
    assert_ne!(
        散乱係数を替えた方針(0.0, 0.0, 0.0).静的キー(),
        散乱係数を替えた方針(-0.0, -0.0, -0.0).静的キー()
    );
}

/// 3成分のうち1つだけが違う方針が同じ鍵へ潰れないことを見る。取り込む順序が固定であることの検査でもある。
#[test]
fn 成分ごとの違いが鍵の違いへ出る() {
    let 基準 = 散乱係数を替えた方針(1e-6, 2e-6, 3e-6).静的キー();
    assert_ne!(基準, 散乱係数を替えた方針(2e-6, 1e-6, 3e-6).静的キー());
    assert_ne!(基準, 散乱係数を替えた方針(1e-6, 2e-6, 4e-6).静的キー());
}
