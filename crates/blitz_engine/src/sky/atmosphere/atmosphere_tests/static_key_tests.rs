//! 大気静的キーの検査。同じ方針が同じ鍵へ写ること、方針のどの値の違いも鍵の違いへ出ることを見る。

use super::policy_variants::一つだけ替えた方針一覧;
use crate::sky::atmosphere::key_digest::大気パラメータ数;
use crate::sky::atmosphere::{レイリー成分, 大気媒体方針, 消散係数RGB};

fn 散乱係数を替えた方針(赤: f32, 緑: f32, 青: f32) -> 大気媒体方針 {
    let 方針 = 大気媒体方針::地球標準();
    let 係数 = 消散係数RGB::毎メートルから(赤, 緑, 青).unwrap();
    let レイリー = レイリー成分::生成する(係数, 方針.レイリー().尺度高度()).unwrap();
    大気媒体方針::生成する(方針.惑星形状(), レイリー, 方針.ミー(), 方針.吸収(), 方針.地表反射率())
}

#[test]
fn 同じ方針は同じ鍵へ写る() {
    assert_eq!(大気媒体方針::地球標準().静的キー(), 大気媒体方針::地球標準().静的キー());
}

/// 鍵が保持する値の個数と、1つだけ替えた方針の件数が一致することを見る。方針へ値を足して鍵の取り込みを増やしたのに
/// 検査の変形を足し忘れた場合も、その逆の場合も、この検査が止める。
#[test]
fn 変形一覧が鍵の全パラメータを覆う() {
    assert_eq!(一つだけ替えた方針一覧().len(), 大気パラメータ数);
}

/// 鍵はビット列の完全比較で等しさを決めるため、1つの値の違いは必ず鍵の違いへ出る。
/// 64ビットへ畳んだ要約だけで比べていた頃は、この検査が通っても衝突する組が残りうる形だった。
#[test]
fn どのパラメータを替えても鍵が変わる() {
    let 基準 = 大気媒体方針::地球標準().静的キー();
    for (名前, 方針) in 一つだけ替えた方針一覧() {
        assert_ne!(基準, 方針.静的キー(), "{名前}の違いが鍵に出ていない");
    }
}

/// 正のゼロと負のゼロは`==`では等しいが別々の値であるため、ビット表現で持つ鍵は両者を区別する。
/// 値の比較で更新を決める契約は「鍵が同じなら大気も同じ」の向きで守られている必要がある。
#[test]
fn 正のゼロと負のゼロを鍵が区別する() {
    assert_ne!(
        散乱係数を替えた方針(0.0, 0.0, 0.0).静的キー(),
        散乱係数を替えた方針(-0.0, -0.0, -0.0).静的キー()
    );
}

/// 3成分のうち1つだけが違う方針が同じ鍵へ潰れないことを見る。取り込む順序が固定であることの検査でもある。
#[test]
fn 成分ごとの違いが鍵の違いへ出る() {
    let 基準 = 散乱係数を替えた方針(1e-6, 2e-6, 3e-6).静的キー();
    assert_ne!(基準, 散乱係数を替えた方針(2e-6, 1e-6, 3e-6).静的キー());
    assert_ne!(基準, 散乱係数を替えた方針(1e-6, 2e-6, 4e-6).静的キー());
}
