//! 成分の中の1つの値だけを替えたものを作る工程。受け取るのは元の値と替える位置、返すのは1箇所だけ違う値である。
//! 替え幅は「元の値と確実に別の浮動小数になり、かつ値オブジェクトの値域を出ない」ことだけを満たせばよい。

use blitz_math::{メートル, 逆メートル};

use crate::sky::atmosphere::{密度分布, 密度分布層, 消散係数RGB};

/// 半径・高度・係数に共通の替え幅。これらは上限を持たないため、同じ幅で足せる。
const ずれ: f32 = 1.0;

/// 0以上1以下、または-1より大きく1より小さい値域を持つ量の替え幅。上の幅では値域を出るため別に持つ。
pub(super) const 割合のずれ: f32 = 0.5;

pub(super) fn 長さをずらす(長さ: メートル) -> メートル {
    メートル::生成する(長さ.値() + ずれ)
}

pub(super) fn 係数の1成分をずらす(係数: 消散係数RGB, 添字: usize) -> 消散係数RGB {
    let mut 成分 = 係数.成分().map(|値| 値.値());
    成分[添字] += ずれ;
    消散係数RGB::毎メートルから(成分[0], 成分[1], 成分[2]).unwrap()
}

pub(super) fn 分布の1係数をずらす(分布: 密度分布, 層添字: usize, 係数添字: usize) -> 密度分布 {
    let mut 層一覧 = 分布.層();
    層一覧[層添字] = 層の1係数をずらす(層一覧[層添字], 係数添字);
    密度分布::生成する(層一覧[0], 層一覧[1])
}

/// 係数の並びは`密度分布層`が値を取り込む順序、すなわち幅・指数項・指数尺度・線形項・定数項である。
fn 層の1係数をずらす(層: 密度分布層, 係数添字: usize) -> 密度分布層 {
    let mut 係数 = [層.幅().値(), 層.指数項(), 層.指数尺度().値(), 層.線形項().値(), 層.定数項()];
    係数[係数添字] += ずれ;
    let (幅, 指数尺度, 線形項) = (メートル::生成する(係数[0]), 逆メートル::生成する(係数[2]), 逆メートル::生成する(係数[3]));
    密度分布層::生成する(幅, 係数[1], 指数尺度, 線形項, 係数[4]).unwrap()
}
