#![allow(clippy::unwrap_used)]

use blitz_math::ラジアン;

use super::{天空状態, 空と太陽の方針, 空放射輝度係数};
use crate::time::世界時刻;

fn 時刻の状態(秒: f64) -> (天空状態, 空と太陽の方針) {
    let 方針 = 空と太陽の方針::既定値();
    let 状態 = super::天空状態を導出する(世界時刻::生成する(blitz_math::大域秒::生成する(秒)).unwrap(), &方針).unwrap();
    (状態, 方針)
}

fn 係数(秒: f64) -> 空放射輝度係数 {
    let (状態, 方針) = 時刻の状態(秒);
    空放射輝度係数::導出する(&状態, &方針).unwrap()
}

#[test]
fn 代表時刻の係数と放射輝度がすべて有限である() {
    for 秒 in [0.0, 21_600.0, 32_400.0, 43_200.0, 54_000.0, 64_800.0, 75_600.0] {
        let 係数 = 係数(秒);
        for 値 in 係数.方向係数().iter().flatten().chain(係数.放射輝度スケール().iter()) {
            assert!(値.is_finite(), "秒{秒}の係数が有限でない: {値}");
        }
        for 天頂角度 in [0.0, 30.0, 60.0, 89.0, 120.0] {
            let 放射輝度 = 係数.放射輝度を評価する(ラジアン::度から(天頂角度), ラジアン::度から(45.0));
            for 値 in 放射輝度 {
                assert!(値.is_finite() && 値 >= 0.0, "秒{秒}・天頂角{天頂角度}度の放射輝度が不正: {値}");
            }
        }
    }
}

/// 太陽が高いほど天頂の空は明るい。昼の3時刻(9時・正午・15時)のうち正午が最大になる。
#[test]
fn 太陽が高いほど天頂の放射輝度が大きい() {
    let 天頂 = ラジアン::生成する(0.0);
    let 太陽との角度 = ラジアン::度から(45.0);
    let 朝 = 係数(32_400.0).放射輝度を評価する(天頂, 太陽との角度);
    let 正午 = 係数(43_200.0).放射輝度を評価する(天頂, 太陽との角度);
    let 夕 = 係数(57_600.0).放射輝度を評価する(天頂, 太陽との角度);
    for チャネル in 0..3 {
        assert!(朝[チャネル] < 正午[チャネル], "チャネル{チャネル}: 朝{:?} >= 正午{:?}", 朝, 正午);
        assert!(夕[チャネル] < 正午[チャネル], "チャネル{チャネル}: 夕{:?} >= 正午{:?}", 夕, 正午);
    }
}

/// 真夜中は昼係数が0であり、評価結果は夜空の最小項そのものになる(定義域外の外挿が混ざらない)。
#[test]
fn 夜は夜空の最小項そのものになる() {
    let 係数 = 係数(0.0);
    let 夜空 = 係数.夜空放射輝度().成分();
    for 天頂角度 in [0.0, 45.0, 89.0] {
        let 放射輝度 = 係数.放射輝度を評価する(ラジアン::度から(天頂角度), ラジアン::度から(30.0));
        assert_eq!(放射輝度, 夜空, "天頂角{天頂角度}度で夜空と一致しない");
    }
}

/// 薄明帯を1秒刻みで横切っても放射輝度が跳ばない。刻みごとの変化が昼側と夜側の差の1割を超えないことを求める。
#[test]
fn 薄明帯の放射輝度が連続に変わる() {
    let 天頂 = ラジアン::生成する(0.0);
    let 太陽との角度 = ラジアン::度から(60.0);
    let 昼側 = 係数(43_200.0).放射輝度を評価する(天頂, 太陽との角度);
    let 許容 = 昼側.iter().fold(0.0f32, |最大, 値| 最大.max(*値)) * 0.1;
    let mut 直前 = 係数(20_000.0).放射輝度を評価する(天頂, 太陽との角度);
    for 刻み in 1..=2_000 {
        let 秒 = 20_000.0 + f64::from(刻み);
        let 今 = 係数(秒).放射輝度を評価する(天頂, 太陽との角度);
        for チャネル in 0..3 {
            assert!(
                (今[チャネル] - 直前[チャネル]).abs() <= 許容,
                "秒{秒}で放射輝度が跳んだ: {直前:?} -> {今:?}"
            );
        }
        直前 = 今;
    }
}
