//! 一日の太陽軌道が太陽天頂区間の境界を跨ぐ瞬間の列挙。担当する工程は「空と太陽の方針と間引きの刻みを受け取り、
//! その世界の一日で天頂余弦が境界を跨ぐ瞬間を、跨ぐ向きと時刻とともに並べて返す」ことである。
//! 時刻から区間を読むことと跨いだ秒を詰めることは`sun_zenith_crossing_search`が持つ。
//!
//! 跨ぎの一覧を検収側の表で持たないために本番と同じ導出へ置く。天頂余弦は空と太陽の方針(緯度・太陽赤緯・
//! 一日の長さ)だけで決まり、区間の分け方は間引きの刻みの設定だけで決まる。どちらかを写した表を別に持つと、
//! 方針や刻みを変えた実行と検収が別の跨ぎを見る。
//!
//! **同じ境界の上りと下りを別の跨ぎとして収める。** 焼く2つの区間の代表天頂余弦は向きによらず同じだが、
//! 遠方環境を消費する側は固定された法線と反射方向をその時刻の完全な太陽方向で太陽相対座標へ写すため、
//! 方位が反対の上りと下りでは立方体画像の別の方向を参照する。左右非対称な世界では画面上の段差が向きで変わりうる。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」

use super::sun_zenith_crossing_search::{区間を求める, 跨いだ秒を挟み撃つ};
use super::{天空状態エラー, 太陽天頂区間, 空と太陽の方針, 跨ぎの方向, 間引きの刻みの設定};

/// 一日を刻む標本の数。既定の一日ではちょうど1秒に当たる。天頂余弦が1秒で動く量は高々7e-5であり、
/// 刻みの初期値の区間の幅0.01の百分の一に満たないため、隣り合う標本が2つ以上の境界を跨ぐことはない。
/// 跨いだ標本が現れたら刻みが極端に細かいことを意味するため、黙って飛ばさずに型付きの失敗にする。
const 一日の標本数: u32 = 86_400;

/// 一日で境界を跨いだ瞬間1つ。上側の区間の下端がその境界の天頂余弦であり、1つ下の区間との境目を指す。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 太陽天頂区間の跨ぎ {
    上側の区間: 太陽天頂区間,
    方向: 跨ぎの方向,
    一日内秒: f64,
}

impl 太陽天頂区間の跨ぎ {
    pub fn 上側の区間(self) -> 太陽天頂区間 {
        self.上側の区間
    }

    pub fn 方向(self) -> 跨ぎの方向 {
        self.方向
    }

    /// 一日の始まりから数えてこの向きで最初に跨いだ秒。段差を撮る実行はこの時刻へ時計を据える。
    pub fn 一日内秒(self) -> f64 {
        self.一日内秒
    }
}

/// 一日で跨ぐ瞬間を、上側の区間識別の昇順・同じ識別なら上りを先にして並べて返す。
pub fn 一日の区間の跨ぎを列挙する(
    方針: &空と太陽の方針,
    刻み: 間引きの刻みの設定,
) -> Result<Vec<太陽天頂区間の跨ぎ>, 天空状態エラー> {
    let 一日の秒数 = f64::from(方針.天球().一日の長さ().秒数().値());
    let mut 一覧: Vec<太陽天頂区間の跨ぎ> = Vec::new();
    let mut 前 = (0.0, 区間を求める(0.0, 方針, 刻み)?.区間識別());
    for 番号 in 1..=一日の標本数 {
        let 秒 = 一日の秒数 * f64::from(番号) / f64::from(一日の標本数);
        let 識別 = 区間を求める(秒, 方針, 刻み)?.区間識別();
        if 識別 != 前.1 {
            let 跨いだ数 = 識別.abs_diff(前.1);
            if 跨いだ数 != 1 {
                return Err(天空状態エラー::値域外("隣り合う標本が跨いだ境界の数", f32::from(跨いだ数)));
            }
            let 方向 = if 識別 > 前.1 {
                跨ぎの方向::上り
            } else {
                跨ぎの方向::下り
            };
            収める(&mut 一覧, (識別.max(前.1), 方向), (前, 秒), (方針, 刻み))?;
        }
        前 = (秒, 識別);
    }
    一覧.sort_by_key(|跨ぎ| (跨ぎ.上側の区間.区間識別(), 跨ぎ.方向));
    Ok(一覧)
}

/// その識別とその向きの組をまだ収めていないときだけ一覧へ足す。同じ向きで同じ境界を2度収めないための唯一の関門である。
/// 一日に同じ向きの跨ぎが2度現れる軌道では、収めるのは先に来たほうである。
fn 収める(
    一覧: &mut Vec<太陽天頂区間の跨ぎ>,
    上側と方向: (u16, 跨ぎの方向),
    下側と上側の秒: ((f64, u16), f64),
    方針と刻み: (&空と太陽の方針, 間引きの刻みの設定),
) -> Result<(), 天空状態エラー> {
    if 一覧.iter().any(|跨ぎ| (跨ぎ.上側の区間.区間識別(), 跨ぎ.方向) == 上側と方向) {
        return Ok(());
    }
    let (方針, 刻み) = 方針と刻み;
    let (下側, 上側の秒) = 下側と上側の秒;
    一覧.push(太陽天頂区間の跨ぎ {
        上側の区間: 太陽天頂区間::識別から作る(上側と方向.0, 刻み)?,
        方向: 上側と方向.1,
        一日内秒: 跨いだ秒を挟み撃つ(下側, 上側の秒, 方針, 刻み)?,
    });
    Ok(())
}
