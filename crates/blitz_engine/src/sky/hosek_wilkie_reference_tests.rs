//! 焼いたデータセットと引き当ての実装が原実装と一致することを、参照値との突き合わせで確かめる。
//! 参照値は原実装(ArHosekSkyModel.cのArHosekSkyModel_CookConfigurationとArHosekSkyModel_CookRadianceConfiguration)を
//! 同じ入力で走らせて得た値である。データセットの並べ方や添字を取り違えると、有限性や単調性の検査は通ってもここで落ちる。

#![allow(clippy::unwrap_used)]

use super::hosek_wilkie;

/// f32へ丸めた表と倍精度の参照値の差を吸収する相対許容。
const 相対許容: f32 = 1.0e-4;

fn 一致を求める(実際: f32, 参照: f32, 説明: &str) {
    let 許容 = 相対許容 * 参照.abs().max(1.0);
    assert!((実際 - 参照).abs() <= 許容, "{説明}: 実際{実際}、参照{参照}");
}

#[test]
fn 濁度3アルベド0点1太陽高度45度の係数が参照値と一致する() {
    let 太陽高度 = std::f32::consts::FRAC_PI_4;
    let 参照 = [
        [
            -1.068_983, -0.160_948, 1.548_184, 2.534_144, -2.980_595, 1.217_501, 0.166_863, 0.772_125, 0.706_867,
        ],
        [
            -1.080_123, -0.178_343, 1.183_661, 1.466_462, -4.870_436, 1.063_816, 0.126_542, 1.840_212, 0.681_29,
        ],
        [
            -1.079_054, -0.211_79, 0.657_741, 0.025_658, -1.260_462, 0.741_378, 0.070_775, 2.759_213, 0.664_3,
        ],
    ];
    let 実際 = hosek_wilkie::方向係数を焼く(3.0, 0.1, 太陽高度);
    for (チャネル, 参照行) in 参照.iter().enumerate() {
        for (係数, 参照値) in 参照行.iter().enumerate() {
            一致を求める(実際[係数][チャネル], *参照値, &format!("チャネル{チャネル}の係数{係数}"));
        }
    }
    let 参照放射輝度 = [6.667_37, 10.071_6, 15.581_828];
    let 実際放射輝度 = hosek_wilkie::放射輝度スケールを焼く(3.0, 0.1, 太陽高度);
    for (チャネル, 参照値) in 参照放射輝度.iter().enumerate() {
        一致を求める(実際放射輝度[チャネル], *参照値, &format!("チャネル{チャネル}の放射輝度スケール"));
    }
}

