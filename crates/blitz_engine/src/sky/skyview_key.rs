//! スカイビューLUTを作り直すかどうかを値の比較で決めるための鍵。
//! 大気静的キーに、太陽の天頂余弦と観測高度を足したものである。
//!
//! 太陽の方位角を鍵へ入れないのは、スカイビューLUTの横軸が太陽に対する相対方位であり、球対称の大気では
//! 太陽の方位をどこへ置いても同じ表になるためである。太陽の放射照度も入れない。LUTは放射照度を1として焼き、
//! 描画側が掛けるためである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「更新の決定性」

use blitz_math::メートル;

use super::atmosphere::大気静的キー;

/// スカイビューLUTの中身を決める値の組。浮動小数をビット表現で持つのは、正のゼロと負のゼロが`==`では
/// 等しいのに別々の値であり、「同じ鍵なら同じLUT」の向きで契約が破れるためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct スカイビューキー {
    大気: 大気静的キー,
    太陽天頂余弦のビット: u32,
    観測高度のビット: u32,
}

impl スカイビューキー {
    pub fn 導く(大気: 大気静的キー, 太陽天頂余弦: f32, 観測高度: メートル) -> Self {
        Self {
            大気,
            太陽天頂余弦のビット: 太陽天頂余弦.to_bits(),
            観測高度のビット: 観測高度.値().to_bits(),
        }
    }

    /// 大気の部分だけを取り出す。透過率と多重散乱を焼き直すかどうかはこちらだけで決まる。
    pub fn 大気の鍵(&self) -> 大気静的キー {
        self.大気
    }
}
