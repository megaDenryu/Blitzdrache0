//! 遠方環境の立方体画像を焼き直すかどうかを値の比較で決めるための鍵。
//! スカイビューキーに、太陽放射照度と夜空放射輝度を足したものである。
//!
//! スカイビューキーをそのまま流用できないのは、遠方環境の実画素がこの2つの方針値も掛けた後の値だからである。
//! 流用すると、空描画方針の明るさだけを変えたときに古い遠方環境を参照し続ける。
//!
//! 太陽円盤放射輝度を鍵へ入れないのは、遠方環境が円盤を除いた連続な天空放射輝度だけを保持するためである。
//! 円盤は直接光の経路として別に数えるため、円盤の明るさを変えても遠方環境の画素は1つも変わらない。
//!
//! 太陽の方位を鍵へ入れないのは、遠方環境を太陽相対座標で焼くためである。同じ高度で方位だけが動いた太陽は
//! 座標系ごと回るため、焼いた内容が変わらない(参照: `_doc/設計/放射輝度問い合わせ階層.md`「鍵の設計(2つの注意)」)。

use super::{スカイビューキー, 放射輝度色};

/// 遠方環境の中身を決める値の組。浮動小数をビット表現で持つのは、正のゼロと負のゼロが`==`では等しいのに
/// 別々の値であり、「同じ鍵なら同じ画像」の向きで契約が破れるためである(スカイビューキーと同じ理由)。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct 遠方環境キー {
    スカイビュー: スカイビューキー,
    太陽放射照度のビット: u32,
    夜空放射輝度のビット: [u32; 3],
}

impl 遠方環境キー {
    pub fn 導く(スカイビュー: スカイビューキー, 太陽放射照度: f32, 夜空放射輝度: 放射輝度色) -> Self {
        Self {
            スカイビュー,
            太陽放射照度のビット: 太陽放射照度.to_bits(),
            夜空放射輝度のビット: 夜空放射輝度.成分().map(f32::to_bits),
        }
    }

    /// スカイビューの部分だけを取り出す。遠方環境が読む表を焼き直すかどうかはこちらだけで決まる。
    pub fn スカイビューの鍵(&self) -> スカイビューキー {
        self.スカイビュー
    }
}
