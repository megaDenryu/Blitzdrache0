//! 空を描くときだけ要る設定。時刻では決まらず、シーンが構築時に選ぶ。

use blitz_math::ラジアン;

use super::default_constant::確定値;
use super::{地表アルベド, 天空状態エラー, 放射輝度色};

/// 既定の地表アルベド。無彩色の土や草地に相当する低い反射率であり、解析近似の代表値として使われる値である。
const 既定の地表アルベド: f32 = 0.1;
/// 解析近似が返す放射輝度をこのエンジンの明るさへ合わせる倍率。
/// 近似の出力は物理単位(kcd毎平方メートル級)で1から30程度に及び、方向光強度3.0を基準に組んだ既存の絵とは尺度が違う。
///
/// 注意: この値は`cargo xtask sky-time`の判定と結び付いている。4時刻すべてで空に飽和画素が出ないことと、
/// 太陽円盤だけが飽和することを同じ絵で確かめているため、倍率を動かすとどちらかの判定が落ちる。
/// 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「実装の対応」
const 既定の放射輝度倍率: f32 = 0.06;
/// 夜空の最小項。太陽が地平線より下の間はこの暗い放射輝度へ寄せる。0にしないのは、空が完全な黒へ落ちると
/// 空と未描画領域が画素で区別できなくなるためである。
const 既定の夜空放射輝度: [f32; 3] = [0.002, 0.002, 0.004];
/// 太陽円盤の放射輝度。トーンマップの飽和域より十分上に置き、円盤が白く抜けてブルームを伴うようにする。
const 既定の太陽円盤放射輝度: [f32; 3] = [8.0, 7.6, 6.8];
/// 太陽円盤の角半径。地球から見た太陽の視半径である。
const 既定の太陽円盤角半径の度: f32 = 0.27;

/// 空パスが要る設定一式。太陽方向や濁度のような時刻から決まる値は含まない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 空描画方針 {
    地表アルベド: 地表アルベド,
    放射輝度倍率: f32,
    夜空放射輝度: 放射輝度色,
    太陽円盤放射輝度: 放射輝度色,
    太陽円盤角半径: ラジアン,
}

impl 空描画方針 {
    pub fn 生成する(
        地表アルベド: 地表アルベド,
        放射輝度倍率: f32,
        夜空放射輝度: 放射輝度色,
        太陽円盤放射輝度: 放射輝度色,
        太陽円盤角半径: ラジアン,
    ) -> Result<Self, 天空状態エラー> {
        if !放射輝度倍率.is_finite() || 放射輝度倍率 <= 0.0 {
            return Err(天空状態エラー::値域外("放射輝度倍率", 放射輝度倍率));
        }
        let 半径 = 太陽円盤角半径.値();
        if !半径.is_finite() || 半径 <= 0.0 || 半径 >= std::f32::consts::FRAC_PI_2 {
            return Err(天空状態エラー::値域外("太陽円盤角半径", 半径));
        }
        Ok(Self {
            地表アルベド,
            放射輝度倍率,
            夜空放射輝度,
            太陽円盤放射輝度,
            太陽円盤角半径,
        })
    }

    pub fn 既定値() -> Self {
        確定値(Self::生成する(
            確定値(地表アルベド::生成する(既定の地表アルベド)),
            既定の放射輝度倍率,
            確定値(色を作る(既定の夜空放射輝度)),
            確定値(色を作る(既定の太陽円盤放射輝度)),
            ラジアン::度から(既定の太陽円盤角半径の度),
        ))
    }

    pub fn 地表アルベド(&self) -> 地表アルベド {
        self.地表アルベド
    }

    pub fn 放射輝度倍率(&self) -> f32 {
        self.放射輝度倍率
    }

    pub fn 夜空放射輝度(&self) -> 放射輝度色 {
        self.夜空放射輝度
    }

    pub fn 太陽円盤放射輝度(&self) -> 放射輝度色 {
        self.太陽円盤放射輝度
    }

    pub fn 太陽円盤角半径(&self) -> ラジアン {
        self.太陽円盤角半径
    }
}

fn 色を作る(成分: [f32; 3]) -> Result<放射輝度色, 天空状態エラー> {
    放射輝度色::生成する(成分[0], 成分[1], 成分[2])
}
