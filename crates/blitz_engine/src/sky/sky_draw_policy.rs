//! 空を描くときだけ要る設定。時刻では決まらず、シーンが構築時に選ぶ。
//! 既定値とその根拠は`default`が持つ。

mod default;

use blitz_math::{メートル, ラジアン};

use super::{地表アルベド, 天空状態エラー, 放射輝度色};

/// 空パスが要る設定一式。太陽方向や濁度のような時刻から決まる値は含まない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 空描画方針 {
    地表アルベド: 地表アルベド,
    放射輝度倍率: f32,
    夜空放射輝度: 放射輝度色,
    太陽円盤放射輝度: 放射輝度色,
    太陽円盤角半径: ラジアン,
    観測高度: メートル,
}

impl 空描画方針 {
    pub fn 生成する(
        地表アルベド: 地表アルベド,
        放射輝度倍率: f32,
        夜空放射輝度: 放射輝度色,
        太陽円盤放射輝度: 放射輝度色,
        太陽円盤角半径: ラジアン,
        観測高度: メートル,
    ) -> Result<Self, 天空状態エラー> {
        if !放射輝度倍率.is_finite() || 放射輝度倍率 <= 0.0 {
            return Err(天空状態エラー::値域外("放射輝度倍率", 放射輝度倍率));
        }
        let 半径 = 太陽円盤角半径.値();
        if !半径.is_finite() || 半径 <= 0.0 || 半径 >= std::f32::consts::FRAC_PI_2 {
            return Err(天空状態エラー::値域外("太陽円盤角半径", 半径));
        }
        if !観測高度.値().is_finite() || 観測高度.値() < 0.0 {
            return Err(天空状態エラー::値域外("観測高度", 観測高度.値()));
        }
        Ok(Self {
            地表アルベド,
            放射輝度倍率,
            夜空放射輝度,
            太陽円盤放射輝度,
            太陽円盤角半径,
            観測高度,
        })
    }

    pub fn 既定値() -> Self {
        default::既定値()
    }

    pub fn 地表アルベド(&self) -> 地表アルベド {
        self.地表アルベド
    }

    pub fn 放射輝度倍率(&self) -> f32 {
        self.放射輝度倍率
    }

    pub fn 夜空放射輝度(&self) -> 放射輝度色 {
        self.夜空放射輝度
    }

    pub fn 太陽円盤放射輝度(&self) -> 放射輝度色 {
        self.太陽円盤放射輝度
    }

    pub fn 太陽円盤角半径(&self) -> ラジアン {
        self.太陽円盤角半径
    }

    /// スカイビューLUTを焼く観測点の、地表からの高さ。
    pub fn 観測高度(&self) -> メートル {
        self.観測高度
    }
}
