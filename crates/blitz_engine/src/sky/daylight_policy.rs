//! 昼と夜で変わる環境光・露出補正段と、その間をつなぐ薄明帯の設定。

use blitz_math::ラジアン;

use super::default_constant::確定値;
use super::{天空状態エラー, 昼係数, 環境光強度, 露出補正段};

/// 太陽高度が地平線からこの角度だけ下がるまでを昼夜の移行帯とする。市民薄明の定義と同じ6度を既定に置く。
const 既定の薄明帯の幅の度: f32 = 6.0;
/// 昼の環境光係数。既存の既定ライティングの環境光と同じ値である。
const 既定の昼の環境光強度: f32 = 0.03;
/// 夜の環境光係数。月と星の照り返しに相当する下限であり、0にすると影の側が完全な黒へ落ちる。
const 既定の夜の環境光強度: f32 = 0.005;
/// 昼の露出補正段。昼を基準に置くため補正しない。
const 既定の昼の露出補正段: f32 = 0.0;
/// 夜の露出補正段。太陽光と空の放射輝度そのものが下がるため、見え方の底上げを2段だけ与える。
const 既定の夜の露出補正段: f32 = 2.0;

/// 昼と夜の値と、その間を滑らかにつなぐ帯の幅。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 昼夜方針 {
    薄明帯の幅: ラジアン,
    昼の環境光強度: 環境光強度,
    夜の環境光強度: 環境光強度,
    昼の露出補正段: 露出補正段,
    夜の露出補正段: 露出補正段,
}

impl 昼夜方針 {
    pub fn 生成する(
        薄明帯の幅: ラジアン,
        昼の環境光強度: 環境光強度,
        夜の環境光強度: 環境光強度,
        昼の露出補正段: 露出補正段,
        夜の露出補正段: 露出補正段,
    ) -> Result<Self, 天空状態エラー> {
        if !薄明帯の幅.値().is_finite() || 薄明帯の幅.値() <= 0.0 {
            return Err(天空状態エラー::値域外("薄明帯の幅", 薄明帯の幅.値()));
        }
        Ok(Self {
            薄明帯の幅,
            昼の環境光強度,
            夜の環境光強度,
            昼の露出補正段,
            夜の露出補正段,
        })
    }

    pub fn 既定値() -> Self {
        Self {
            薄明帯の幅: ラジアン::度から(既定の薄明帯の幅の度),
            昼の環境光強度: 確定値(環境光強度::生成する(既定の昼の環境光強度)),
            夜の環境光強度: 確定値(環境光強度::生成する(既定の夜の環境光強度)),
            昼の露出補正段: 確定値(露出補正段::生成する(既定の昼の露出補正段)),
            夜の露出補正段: 確定値(露出補正段::生成する(既定の夜の露出補正段)),
        }
    }

    pub fn 昼係数に応じた環境光(&self, 昼係数: 昼係数) -> Result<環境光強度, 天空状態エラー> {
        self.夜の環境光強度.混ぜる(&self.昼の環境光強度, 昼係数.値())
    }

    pub fn 昼係数に応じた露出補正段(&self, 昼係数: 昼係数) -> Result<露出補正段, 天空状態エラー> {
        self.夜の露出補正段.混ぜる(&self.昼の露出補正段, 昼係数.値())
    }

    pub fn 薄明帯の幅(&self) -> ラジアン {
        self.薄明帯の幅
    }
}
