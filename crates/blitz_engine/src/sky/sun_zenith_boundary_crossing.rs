//! 時刻から太陽天頂区間を読む写像と、その上で区間が変わる時刻を詰める工程。受け取るのは一日内秒と方針と刻み、
//! 返すのは区間、または区間が変わる一日内秒である。
//!
//! 境界の列挙から分けるのは、列挙が「どの境界を収めるか」を決めるのに対し、ここは「ある時刻の区間は何か」と
//! 「区間が変わるのはいつか」だけを答えるためである。呼び出し元は詰め方を1つも知らずに時刻を受け取れる。

use blitz_math::大域秒;

use super::{天空状態を導出する, 天空状態エラー, 太陽天頂区間, 空と太陽の方針, 間引きの刻みの設定};
use crate::time::世界時刻;

/// 区間が変わる時刻を挟み撃ちで詰める回数。一日の秒数を2の40乗で割った幅まで狭まり、既定の一日では十億分の一秒未満になる。
const 挟み撃ちの回数: u32 = 40;

/// 一日内秒の太陽の天頂余弦が属する区間。時刻の紀元は一日の始まりであるため、秒がそのまま一日内時刻になる。
pub(super) fn 区間を求める(
    一日内秒: f64,
    方針: &空と太陽の方針,
    刻み: 間引きの刻みの設定,
) -> Result<太陽天頂区間, 天空状態エラー> {
    let 状態 = 天空状態を導出する(世界時刻::生成する(大域秒::生成する(一日内秒))?, 方針)?;
    太陽天頂区間::属する区間(状態.太陽方向().成分()[1], 刻み)
}

/// 下側の秒とその区間識別、区間が既に変わっている上側の秒を受け取り、区間が変わる秒を挟み撃ちで詰めて返す。
/// 返すのは上側であり、その秒では既に別の区間に入っている。
pub(super) fn 跨いだ秒を挟み撃つ(
    下側: (f64, u16),
    上側の秒: f64,
    方針: &空と太陽の方針,
    刻み: 間引きの刻みの設定,
) -> Result<f64, 天空状態エラー> {
    let (mut 下, mut 上) = (下側.0, 上側の秒);
    for _ in 0..挟み撃ちの回数 {
        let 中 = f64::midpoint(下, 上);
        if 区間を求める(中, 方針, 刻み)?.区間識別() == 下側.1 {
            下 = 中;
        } else {
            上 = 中;
        }
    }
    Ok(上)
}
