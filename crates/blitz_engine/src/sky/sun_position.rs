//! 太陽の位置を求める工程。受け取るのは一日内時刻と観測地の緯度・太陽赤緯、返すのは時角と太陽方向である。

use blitz_math::ラジアン;

use super::{天空状態エラー, 太陽方向};
use crate::time::一日内時刻;

/// 一日内時刻から時角を求める。時角は南中で0、西向きに増える角であり、一日の半ばを南中に置く。
pub(super) fn 時角を求める(一日内時刻: 一日内時刻) -> ラジアン {
    ラジアン::生成する((一日内時刻.位相() - 0.5) * std::f32::consts::TAU)
}

/// 赤道座標(時角 h・太陽赤緯 δ)から地平座標の太陽方向を求める球面天文学の標準変換。
///
/// 東成分 = -cos δ sin h、北成分 = sin δ cos φ - cos δ sin φ cos h、天頂成分 = sin δ sin φ + cos δ cos φ cos h
/// (φ は観測地の緯度)。ワールドの Z 軸は南を向くため、北成分の符号を反転して渡す。
/// 3成分は単位ベクトルの回転であるため長さ1になり、係数はすべて三角関数から出るのでマジック係数を持たない。
pub(super) fn 太陽方向を求める(
    時角: ラジアン, 緯度: ラジアン, 太陽赤緯: ラジアン
) -> Result<太陽方向, 天空状態エラー> {
    let (時角の正弦, 時角の余弦) = 時角.値().sin_cos();
    let (緯度の正弦, 緯度の余弦) = 緯度.値().sin_cos();
    let (赤緯の正弦, 赤緯の余弦) = 太陽赤緯.値().sin_cos();
    let 東 = -赤緯の余弦 * 時角の正弦;
    let 北 = 赤緯の正弦 * 緯度の余弦 - 赤緯の余弦 * 緯度の正弦 * 時角の余弦;
    let 天頂 = 赤緯の正弦 * 緯度の正弦 + 赤緯の余弦 * 緯度の余弦 * 時角の余弦;
    太陽方向::生成する(東, 天頂, -北)
}
