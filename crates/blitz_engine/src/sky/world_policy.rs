//! 世界ごとの空の方針。その世界が空を持つかどうかと、持つ場合の空と太陽の方針・既定時刻を表す。
//!
//! 空を持つ世界は、絵の空だけでなく方向光・環境光・露出も時刻から導く。空を持たない世界はどれも世界が決めた固定値であり、
//! 時刻を1度も読まない。この区別を起動指定でなく世界の方針が持つのは、検証世界の絵が起動指定の有無で動かないようにするためである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「時刻の型」

use blitz_math::大域秒;

use super::空と太陽の方針;
use crate::time::世界時刻;

/// 空を持つ世界の既定時刻。既定の一日の長さでの11時である。
/// 緯度35度・太陽赤緯0度でのこの時刻の太陽は高度52.3度にあり、既定ライティングの方向光との向きの差が10.7度に収まる。
/// 色・強度・環境光・露出倍率は既定ライティングと一致するため、ライティングを時刻へ配線しても明るさの基準が動かない。
const 既定時刻の秒: f64 = 39_600.0;

/// 世界が空を持つかどうか。
///
/// 空ありの側が大気媒体方針(30個の数値)を抱えるため、この列挙は空なしの側でも同じ大きさを占める。
/// 箱に入れて小さくしないのは、この値が起動時に世界ごと1つだけ作られて即座に読み終わる一時値であり、
/// 節約できる量が高々240バイトであるのに対し、`Copy`を失うと方針を配る全経路が借用の寿命を持つためである。
#[allow(clippy::large_enum_variant)]
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 世界の空方針 {
    空なし, // 時刻を持たない。空を描かず、ライティングと露出は固定値
    空あり {
        // 空・方向光・環境光・露出のすべてをこの方針と時刻から導く
        空と太陽: 空と太陽の方針,
        既定時刻: 世界時刻,
    },
}

impl 世界の空方針 {
    /// 空を持つ世界の既定。緯度・大気媒体・一日の長さは`空と太陽の方針`の既定値であり、既定時刻は11時である。
    pub fn 空ありの既定() -> Self {
        Self::空あり {
            空と太陽: 空と太陽の方針::既定値(),
            既定時刻: 既定の世界時刻(),
        }
    }
}

/// 定数から作るため、ここでの失敗は定数が有限でないことを意味する(プログラムのバグ)。
fn 既定の世界時刻() -> 世界時刻 {
    世界時刻::生成する(大域秒::生成する(既定時刻の秒)).unwrap_or_else(|誤り| panic!("空ありの世界の既定時刻が不正だった: {誤り}"))
}
