//! 太陽天頂区間の境界を跨ぐ向き。天頂余弦が増える側へ移るのが上り、減る側へ移るのが下りである。
//!
//! 跨ぎの列挙と別の型にするのは、この向きが跨ぎの一部であると同時に、書き出すファイル名と報告の語彙でも
//! あるためである。ASCIIの呼び名をここが所有することで、検収の側がパスの語を別に決めることがなくなる。
//!
//! 向きを区別する理由は跨ぎの列挙が持つ。焼く2つの区間の代表天頂余弦は向きによらず同じだが、
//! 遠方環境を消費する側が太陽相対座標へ写すため、方位が反対の上りと下りでは参照する方向が変わる。

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum 跨ぎの方向 {
    上り,
    下り,
}

impl 跨ぎの方向 {
    /// 書き出すファイル名と報告に使う語。パスはASCIIで保つ。
    pub fn 呼び名(self) -> &'static str {
        match self {
            Self::上り => "up",
            Self::下り => "down",
        }
    }
}
