//! 時刻から導く方向光の色。

use super::天空状態エラー;

/// 線形空間のRGB三成分で表す太陽光の色。各成分は有限かつ0以上である。
/// レンダラー境界の光色へはライティング入力を組み立てる段で変換する。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 太陽光色 {
    成分: [f32; 3],
}

impl 太陽光色 {
    pub fn 生成する(赤: f32, 緑: f32, 青: f32) -> Result<Self, 天空状態エラー> {
        let 成分 = [赤, 緑, 青];
        if let Some(不正) = 成分.iter().find(|値| !値.is_finite() || **値 < 0.0) {
            return Err(天空状態エラー::値域外("太陽光色の成分", *不正));
        }
        Ok(Self { 成分 })
    }

    pub fn 成分(&self) -> [f32; 3] {
        self.成分
    }

    /// 自身を係数0、相手を係数1として線形に混ぜる。両端が値域内であるため結果も値域内に収まる。
    pub fn 混ぜる(&self, 相手: &Self, 係数: f32) -> Result<Self, 天空状態エラー> {
        let 混ぜた = [0, 1, 2].map(|添字| self.成分[添字] + (相手.成分[添字] - self.成分[添字]) * 係数);
        Self::生成する(混ぜた[0], 混ぜた[1], 混ぜた[2])
    }
}
