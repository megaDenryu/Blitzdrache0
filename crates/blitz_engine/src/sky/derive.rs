//! 世界時刻から天空状態を導く純関数。同一の世界時刻と同一の方針からは常に同一の天空状態が得られる。
//! この層は絵を知らず、レンダラーへの配線は別の段が行う。

use blitz_math::ラジアン;

use super::sun_position::{太陽方向を求める, 時角を求める};
use super::{天空状態, 天空状態エラー, 影の有効性, 昼係数, 空と太陽の方針, 空の係数};
use crate::time::世界時刻;

/// 空と太陽方針の本体。時刻を一日内へ還元し、太陽の位置と昼夜の連続量から天空状態を組み立てる。
pub fn 天空状態を導出する(時刻: 世界時刻, 方針: &空と太陽の方針) -> Result<天空状態, 天空状態エラー> {
    let 一日内時刻 = 時刻.一日内時刻へ(方針.天球().一日の長さ())?;
    let 時角 = 時角を求める(一日内時刻);
    let 太陽方向 = 太陽方向を求める(時角, 方針.天球().緯度(), 方針.天球().太陽赤緯())?;
    let 太陽高度 = 太陽方向.高度();
    let 昼係数 = 昼係数::太陽高度から求める(太陽高度, 方針.昼夜().薄明帯の幅());
    Ok(天空状態 {
        太陽方向,
        太陽高度,
        方向光色: 方針.太陽光().高度に応じた色(太陽高度)?,
        方向光強度: 方針.太陽光().昼係数に応じた強度(昼係数)?,
        環境光強度: 方針.昼夜().昼係数に応じた環境光(昼係数)?,
        露出補正段: 方針.昼夜().昼係数に応じた露出補正段(昼係数)?,
        空の係数: 空の係数::生成する(天頂角を求める(太陽高度), 方針.濁度()),
        影の有効性: 影の有効性::昼係数から決める(昼係数),
        昼係数,
    })
}

/// 天頂から測った太陽の角度。高度が地平線より下なら直角を超える。
fn 天頂角を求める(太陽高度: ラジアン) -> ラジアン {
    ラジアン::生成する(std::f32::consts::FRAC_PI_2) - 太陽高度
}
