//! 昼夜の連続性の検査: 地平線をまたぐ帯と日境界で、時刻を微小に動かしたときの出力の跳びが小さいことを見る。
//! 太陽高度そのものを入力にできないため、地平線を横切る時刻の前後を細かく刻んで隣り合う標本の差を見る。

#![allow(clippy::unwrap_used)]

use blitz_math::大域秒;

use super::{天空状態, 天空状態を導出する, 空と太陽の方針};
use crate::time::世界時刻;

const 一日の秒数: f64 = 86_400.0;
/// 隣り合う標本の間隔。太陽は1秒で0.0042度しか動かないため、この間隔での差が大きいなら不連続がある。
const 刻み秒: f64 = 1.0;
/// 隣り合う標本で許す出力の差。方向光強度は最大3.0であり、この上限は1秒あたり0.3%の変化に相当する。
const 許容差: f32 = 0.01;

fn 導出する(秒数: f64) -> 天空状態 {
    let 時刻 = 世界時刻::生成する(大域秒::生成する(秒数)).unwrap();
    天空状態を導出する(時刻, &空と太陽の方針::既定値()).unwrap()
}

fn 差を確かめる(前: &天空状態, 後: &天空状態, 秒数: f64) {
    let 対 = [
        ("方向光強度", 前.方向光強度().値(), 後.方向光強度().値()),
        ("環境光強度", 前.環境光強度().値(), 後.環境光強度().値()),
        ("露出補正段", 前.露出補正段().値(), 後.露出補正段().値()),
        ("昼係数", 前.昼係数().値(), 後.昼係数().値()),
    ];
    for (名前, 前の値, 後の値) in 対 {
        let 差 = (後の値 - 前の値).abs();
        assert!(差 <= 許容差, "秒数{秒数}で{名前}が{差}跳んだ(前{前の値} 後{後の値})");
    }
}

#[test]
fn 日の出の帯を連続して横切る() {
    let 開始 = 18_000.0;
    let 終了 = 25_200.0;
    let mut 秒数 = 開始;
    while 秒数 < 終了 {
        差を確かめる(&導出する(秒数), &導出する(秒数 + 刻み秒), 秒数);
        秒数 += 刻み秒;
    }
}

#[test]
fn 日の入りの帯を連続して横切る() {
    let 開始 = 61_200.0;
    let 終了 = 68_400.0;
    let mut 秒数 = 開始;
    while 秒数 < 終了 {
        差を確かめる(&導出する(秒数), &導出する(秒数 + 刻み秒), 秒数);
        秒数 += 刻み秒;
    }
}

#[test]
fn 日境界でも跳ばない() {
    差を確かめる(&導出する(一日の秒数 - 刻み秒), &導出する(一日の秒数), 一日の秒数);
    差を確かめる(&導出する(-刻み秒), &導出する(0.0), 0.0);
}

#[test]
fn 一日を通して跳ばない() {
    let mut 秒数 = 0.0;
    let mut 前 = 導出する(秒数);
    while 秒数 < 一日の秒数 {
        let 後 = 導出する(秒数 + 刻み秒);
        差を確かめる(&前, &後, 秒数);
        前 = 後;
        秒数 += 刻み秒;
    }
}
