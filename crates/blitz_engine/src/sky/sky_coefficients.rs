//! 空の放射輝度を評価するための入力束。

use blitz_math::ラジアン;

use super::濁度;

/// 解析近似で空の放射輝度を評価するときに要る、時刻から決まる入力の束。
/// 近似式そのもの(Hosek-Wilkieの係数評価)は空パスを入れる段が持ち、この段はその入力だけを運ぶ。
/// 太陽天頂角が直角を超える(太陽が地平線より下にある)間は近似の定義域外であり、外挿してはならない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 空の係数 {
    太陽天頂角: ラジアン,
    濁度: 濁度,
}

impl 空の係数 {
    pub fn 生成する(太陽天頂角: ラジアン, 濁度: 濁度) -> Self {
        Self { 太陽天頂角, 濁度 }
    }

    pub fn 太陽天頂角(&self) -> ラジアン {
        self.太陽天頂角
    }

    pub fn 濁度(&self) -> 濁度 {
        self.濁度
    }
}
