//! データセットの制御点6個を太陽高度で補間する工程。担当するのは「制御点の読み取り方と補間の位置を受け取り1つの値を返す」ことである。
//! 原実装(ArHosekSkyModel.c の ArHosekSkyModel_CookConfiguration)と同じ5次のベジエ曲線であり、
//! 補間の位置は太陽高度を直角で割った比の立方根である。低い太陽ほど値の変化が速いため、この歪めた位置で等間隔の制御点を置いている。

/// 補間の位置。0が地平線、1が天頂である。
pub(super) fn 補間位置(太陽高度: f32) -> f32 {
    let 比 = (太陽高度 / std::f32::consts::FRAC_PI_2).clamp(0.0, 1.0);
    比.cbrt()
}

/// 6個の制御点を`読む(段)`で取り出し、位置`t`の5次ベジエ値を返す。
pub(super) fn 評価する(位置: f32, 読む: impl Fn(usize) -> f32) -> f32 {
    let t = 位置;
    let u = 1.0 - t;
    let 重み一覧 = [
        u * u * u * u * u,
        5.0 * u * u * u * u * t,
        10.0 * u * u * u * t * t,
        10.0 * u * u * t * t * t,
        5.0 * u * t * t * t * t,
        t * t * t * t * t,
    ];
    重み一覧.iter().enumerate().map(|(段, 重み)| 重み * 読む(段)).sum()
}
