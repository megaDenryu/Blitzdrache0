//! データセットを濁度・地表アルベド・太陽高度で引き当てる工程。担当するのは「この3つを受け取り、方向係数9個×3チャネルと
//! 放射輝度スケール3チャネルを返す」ことである。原実装のArHosekSkyModel_CookConfigurationおよび
//! ArHosekSkyModel_CookRadianceConfigurationと同じ、アルベド2段・濁度2段の4隅の重み付き和である。

use super::bezier;
use super::dataset;

/// 引き当てに使う4隅の1つ。アルベドと濁度の両端のどちらを読み、どれだけの重みを掛けるかを持つ。
struct 補間の隅 {
    アルベド1側か: bool,
    濁度段: usize,
    重み: f32,
}

pub(in crate::sky) fn 方向係数を焼く(
    濁度: f32, 地表アルベド: f32, 太陽高度: f32
) -> [[f32; dataset::チャネル数]; dataset::係数数] {
    let 位置 = bezier::補間位置(太陽高度);
    let 隅一覧 = 四隅を作る(濁度, 地表アルベド);
    let mut 結果 = [[0.0; dataset::チャネル数]; dataset::係数数];
    for (係数, 行) in 結果.iter_mut().enumerate() {
        for (チャネル, 値) in 行.iter_mut().enumerate() {
            *値 = 隅一覧
                .iter()
                .map(|隅| {
                    let 先頭 = 方向係数の先頭(隅) + 係数;
                    隅.重み * bezier::評価する(位置, |制御点| dataset::方向係数(チャネル, 先頭 + dataset::係数数 * 制御点))
                })
                .sum();
        }
    }
    結果
}

pub(in crate::sky) fn 放射輝度スケールを焼く(濁度: f32, 地表アルベド: f32, 太陽高度: f32) -> [f32; dataset::チャネル数] {
    let 位置 = bezier::補間位置(太陽高度);
    let 隅一覧 = 四隅を作る(濁度, 地表アルベド);
    let mut 結果 = [0.0; dataset::チャネル数];
    for (チャネル, 値) in 結果.iter_mut().enumerate() {
        *値 = 隅一覧
            .iter()
            .map(|隅| {
                let 先頭 = 放射輝度の先頭(隅);
                隅.重み * bezier::評価する(位置, |制御点| dataset::放射輝度(チャネル, 先頭 + 制御点))
            })
            .sum();
    }
    結果
}

fn 方向係数の先頭(隅: &補間の隅) -> usize {
    let アルベド開始 = if 隅.アルベド1側か {
        dataset::方向係数のアルベド1開始
    } else {
        0
    };
    アルベド開始 + dataset::係数数 * dataset::制御点数 * 隅.濁度段
}

fn 放射輝度の先頭(隅: &補間の隅) -> usize {
    let アルベド開始 = if 隅.アルベド1側か {
        dataset::放射輝度のアルベド1開始
    } else {
        0
    };
    アルベド開始 + dataset::制御点数 * 隅.濁度段
}

fn 四隅を作る(濁度: f32, 地表アルベド: f32) -> [補間の隅; 4] {
    let (低い段, 端数) = 濁度の段と端数(濁度);
    let アルベド = 地表アルベド.clamp(0.0, 1.0);
    [
        (false, 低い段, (1.0 - アルベド) * (1.0 - 端数)),
        (true, 低い段, アルベド * (1.0 - 端数)),
        (false, 低い段 + 1, (1.0 - アルベド) * 端数),
        (true, 低い段 + 1, アルベド * 端数),
    ]
    .map(|(アルベド1側か, 濁度段, 重み)| 補間の隅 {
        アルベド1側か, 濁度段, 重み
    })
}

/// 濁度1〜10の整数段のうち低い側(0基点)と、そこからの端数。濁度10のときは低い側を8段目に置いて端数1とし、
/// 高い側の添字が常にデータセットの中へ収まるようにする。
fn 濁度の段と端数(濁度: f32) -> (usize, f32) {
    let 制限 = 濁度.clamp(1.0, 10.0);
    let (mut 段, mut 段の濁度) = (0usize, 1.0f32);
    while 段 + 2 < dataset::濁度段数 && 段の濁度 + 1.0 <= 制限 {
        段 += 1;
        段の濁度 += 1.0;
    }
    (段, (制限 - 段の濁度).clamp(0.0, 1.0))
}
