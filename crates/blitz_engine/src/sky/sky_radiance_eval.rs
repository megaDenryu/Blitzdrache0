//! 係数と向きから放射輝度を求める工程。担当するのは「見る向きの天頂角と太陽との角度を受け取り、RGBの放射輝度を返す」ことである。
//! 空パスのフラグメントシェーダーと同じ式をCPU側でも持ち、係数の性質(有限性・太陽高度による単調性・夜空への連続な移行)を
//! テストで確かめられるようにする。太陽円盤の重ね合わせはシェーダー側だけが持ち、ここは空の地の放射輝度までを担う。

use blitz_math::ラジアン;

use super::hosek_wilkie;
use super::空放射輝度係数;

/// 分母が0にならないよう天頂方向の余弦へ足す下駄。原実装と同じ値である。
const 余弦の下駄: f32 = 0.01;

impl 空放射輝度係数 {
    /// 昼側の解析近似と夜空の最小項を昼係数で混ぜた放射輝度。
    ///
    /// 注意: 天頂角が直角を超える向き(地平線より下)は近似の定義域外であるため、余弦を0で頭打ちにして地平線の値を保つ。
    pub fn 放射輝度を評価する(&self, 天頂角: ラジアン, 太陽との角度: ラジアン) -> [f32; hosek_wilkie::チャネル数] {
        let 天頂余弦 = 天頂角.値().cos().clamp(0.0, 1.0);
        let 太陽余弦 = 太陽との角度.値().cos().clamp(-1.0, 1.0);
        let 昼係数 = self.昼係数().値();
        let 夜 = self.夜空放射輝度().成分();
        let mut 結果 = [0.0; hosek_wilkie::チャネル数];
        for (チャネル, 値) in 結果.iter_mut().enumerate() {
            let 昼 = 昼側の放射輝度(self, チャネル, 天頂余弦, 太陽余弦, 太陽との角度.値());
            *値 = 夜[チャネル] + (昼 - 夜[チャネル]) * 昼係数;
        }
        結果
    }
}

/// Hosek-Wilkieの放射輝度式F(theta, gamma)に放射輝度スケールを掛けた値。原実装のArHosekSkyModel_GetRadianceInternalと同じ形である。
fn 昼側の放射輝度(係数: &空放射輝度係数, チャネル: usize, 天頂余弦: f32, 太陽余弦: f32, 太陽との角度: f32) -> f32 {
    let 係数値 = 係数.方向係数().map(|行| 行[チャネル]);
    let 指数項 = (係数値[4] * 太陽との角度).exp();
    let レイリー項 = 太陽余弦 * 太陽余弦;
    let ミー分母 = (1.0 + 係数値[8] * 係数値[8] - 2.0 * 係数値[8] * 太陽余弦).max(f32::EPSILON);
    let ミー項 = (1.0 + 太陽余弦 * 太陽余弦) / ミー分母.powf(1.5);
    let 天頂項 = 天頂余弦.sqrt();
    let 地平の伸び = 1.0 + 係数値[0] * (係数値[1] / (天頂余弦 + 余弦の下駄)).exp();
    let 方向項 = 係数値[2] + 係数値[3] * 指数項 + 係数値[5] * レイリー項 + 係数値[6] * ミー項 + 係数値[7] * 天頂項;
    (地平の伸び * 方向項 * 係数.放射輝度スケール()[チャネル]).max(0.0)
}
