//! 太陽天頂区間の中央の天頂余弦。遠方環境の焼く入力はすべてこの値から作る。
//!
//! 生の単精度と別の型にするのは、時計が毎フレーム動かす連続な天頂余弦と取り違えると、
//! 間引きが効かないまま「鍵は変わらないのに焼く内容だけが変わる」経路ができるためである。

/// 不変条件: 値は有限であり、開区間(-1, +1)に入る。区間の中央であるため値域の両端そのものにはならない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 代表天頂余弦 {
    値: f32,
}

impl 代表天頂余弦 {
    /// 前提: 呼び出せるのは同じモジュール木の`太陽天頂区間`だけであり、不変条件はそちらの導出が保証する。
    pub(super) fn 生成する(値: f32) -> Self {
        Self { 値 }
    }

    pub fn 値(self) -> f32 {
        self.値
    }
}
