//! 空描画方針の既定値と、それぞれの値をその大きさに置いた根拠。
//!
//! 値と根拠を1つの場所に置くのは、これらが検収の判定と結び付いており、数字だけを見て動かすと絵の検査が落ちるためである。
//! どの値も「この世界の空をどう見せるか」という表示側の選択であり、大気そのものの物理量(`atmosphere`の媒体方針)とは別である。

use blitz_math::{メートル, ラジアン};

use super::super::default_constant::確定値;
use super::{天空状態エラー, 放射輝度色, 空描画方針};

/// 夜間の背景放射輝度。太陽が地平線より下でもこの値を常時加算する。昼夜で切り替えないのは、
/// 散乱が日没後に自然に減るため切替の不連続が要らないからである。0にしないのは、空が完全な黒へ落ちると
/// 空と未描画領域が画素で区別できなくなるためである。
const 既定の夜空放射輝度: [f32; 3] = [0.002, 0.002, 0.004];
/// 太陽円盤の放射輝度。明るさの圧縮の飽和域より十分上に置き、円盤が白く抜けて光のにじみを伴うようにする。
const 既定の太陽円盤放射輝度: [f32; 3] = [8.0, 7.6, 6.8];
/// 太陽円盤の角半径。地球から見た太陽の視半径である。
const 既定の太陽円盤角半径の度: f32 = 0.27;
/// スカイビューのベイク済み画像を焼く観測点の、地表からの高さ。目の高さに置く。
///
/// カメラの高度へ追従させないのは、スカイビューのベイク済み画像が1つの観測高度についての表であり、カメラが動くたびに
/// 焼き直すことになるのに対し、地表付近では絵の違いが見えないためである。空の放射輝度が高さで変わる尺度は
/// 空気分子の尺度高度8000メートルであり、100メートルの上下では1パーセント程度しか動かない。
/// 鍵は観測高度を含むため、観測点を高所へ置く世界はこの方針値を変えればベイク済み画像が追従する
/// (カメラ姿勢を鍵へ入れるのは空中遠近の段の担当である)。
const 既定の観測高度メートル: f32 = 1.5;
/// 空の放射輝度へ掛ける太陽の放射照度の尺度。スカイビューのベイク済み画像は放射照度を1として焼くため、
/// この値がベイク済み画像の伝達率をこのエンジンの明るさへ写す。
///
/// 20という大きさは、この尺度を入れる前の絵との釣り合いから決めた。既定時刻11時の条件で
/// スカイビューのベイク済み画像の天頂テクセルが(0.00617, 0.01294, 0.03030)、当時の空の天頂放射輝度が(0.1647, 0.2682, 0.5342)で
/// あり、輝度をほぼ決める緑の比が20.7だったためである。
///
/// 注意: この値は`cargo xtask sky-time`の判定と結び付いている。4時刻すべてで空に飽和画素が出ないことと、
/// 太陽円盤だけが飽和することを同じ絵で確かめているため、尺度を動かすとどちらかの判定が落ちる。
/// 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「空の方式」
const 既定の太陽放射照度: f32 = 20.0;

pub(super) fn 既定値() -> 空描画方針 {
    確定値(空描画方針::生成する(
        確定値(色を作る(既定の夜空放射輝度)),
        確定値(色を作る(既定の太陽円盤放射輝度)),
        ラジアン::度から(既定の太陽円盤角半径の度),
        メートル::生成する(既定の観測高度メートル),
        既定の太陽放射照度,
    ))
}

fn 色を作る(成分: [f32; 3]) -> Result<放射輝度色, 天空状態エラー> {
    放射輝度色::生成する(成分[0], 成分[1], 成分[2])
}
