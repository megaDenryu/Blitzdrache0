//! 空描画方針の既定値と、それぞれの値をその大きさに置いた根拠。
//!
//! 値と根拠を1つの場所に置くのは、これらが検収の判定と結び付いており、数字だけを見て動かすと絵の検査が落ちるためである。
//! どの値も「この世界の空をどう見せるか」という表示側の選択であり、大気そのものの物理量(`atmosphere`の媒体方針)とは別である。

use blitz_math::{メートル, ラジアン};

use super::super::default_constant::確定値;
use super::{地表アルベド, 天空状態エラー, 放射輝度色, 空描画方針};

/// 既定の地表アルベド。無彩色の土や草地に相当する低い反射率であり、解析近似の代表値として使われる値である。
const 既定の地表アルベド: f32 = 0.1;
/// 解析近似が返す放射輝度をこのエンジンの明るさへ合わせる倍率。
/// 近似の出力は物理単位(kcd毎平方メートル級)で1から30程度に及び、方向光強度3.0を基準に組んだ既存の絵とは尺度が違う。
///
/// 注意: この値は`cargo xtask sky-time`の判定と結び付いている。4時刻すべてで空に飽和画素が出ないことと、
/// 太陽円盤だけが飽和することを同じ絵で確かめているため、倍率を動かすとどちらかの判定が落ちる。
/// 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「Hosek-Wilkie(暫定の腕。第7段完了まで既定)」
const 既定の放射輝度倍率: f32 = 0.06;
/// 夜空の最小項。太陽が地平線より下の間はこの暗い放射輝度へ寄せる。0にしないのは、空が完全な黒へ落ちると
/// 空と未描画領域が画素で区別できなくなるためである。
const 既定の夜空放射輝度: [f32; 3] = [0.002, 0.002, 0.004];
/// 太陽円盤の放射輝度。トーンマップの飽和域より十分上に置き、円盤が白く抜けてブルームを伴うようにする。
const 既定の太陽円盤放射輝度: [f32; 3] = [8.0, 7.6, 6.8];
/// 太陽円盤の角半径。地球から見た太陽の視半径である。
const 既定の太陽円盤角半径の度: f32 = 0.27;
/// スカイビューLUTを焼く観測点の、地表からの高さ。目の高さに置く。
///
/// カメラの高度へ追従させないのは、スカイビューLUTが1つの観測高度についての表であり、カメラが動くたびに
/// 焼き直すことになるのに対し、地表付近では絵の違いが見えないためである。空の放射輝度が高さで変わる尺度は
/// 空気分子の尺度高度8000メートルであり、100メートルの上下では1パーセント程度しか動かない。
/// 鍵は観測高度を含むため、観測点を高所へ置く世界はこの方針値を変えればLUTが追従する
/// (カメラ姿勢を鍵へ入れるのは空中遠近の段の担当である)。
const 既定の観測高度メートル: f32 = 1.5;
/// 大気LUT腕が空の放射輝度へ掛ける太陽の放射照度の尺度。スカイビューLUTは放射照度を1として焼くため、
/// この値がLUTの伝達率をこのエンジンの明るさへ写す。
///
/// 値は既存の絵との釣り合いから決めた。既定時刻11時の条件でスカイビューLUTの天頂テクセルは
/// (0.00617, 0.01294, 0.03030)、同じ条件のHosek腕の天頂放射輝度は(0.1647, 0.2682, 0.5342)であり、
/// 比は赤26.7・緑20.7・青17.6である。緑に合わせて20とすると、輝度をほぼ決める緑の成分が4パーセント以内で
/// 一致するため、露出とACESトーンマップの釣り合いが腕の切り替えで動かない。赤と青の残差は2つの方式の
/// 物理モデルの違い(Hillaireの天頂はHosekより青い)であり、尺度の誤りではない。
/// 実測の再現手順は、blitz_appで`スカイビューlutのテクセル値`と`空放射輝度係数::放射輝度を評価する`を
/// 同じ時刻で呼んで比を取ることである。
const 既定の太陽放射照度: f32 = 20.0;

pub(super) fn 既定値() -> 空描画方針 {
    確定値(空描画方針::生成する(
        確定値(地表アルベド::生成する(既定の地表アルベド)),
        既定の放射輝度倍率,
        確定値(色を作る(既定の夜空放射輝度)),
        確定値(色を作る(既定の太陽円盤放射輝度)),
        ラジアン::度から(既定の太陽円盤角半径の度),
        メートル::生成する(既定の観測高度メートル),
        既定の太陽放射照度,
    ))
}

fn 色を作る(成分: [f32; 3]) -> Result<放射輝度色, 天空状態エラー> {
    放射輝度色::生成する(成分[0], 成分[1], 成分[2])
}
