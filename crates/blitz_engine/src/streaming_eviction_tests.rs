use crate::streaming_chunk_world_fixture::{世界を作る, 後始末する, 試験メタデータ};
use crate::streaming_coordinator_fixture::{常駐まで進める, 準備完了を待つ, 起動する, 進める};
use crate::{ストリーミングメモリ量, チャンクメモリ量を見積もる, チャンク座標, 予算判定};

/// 常駐1件が数えるVRAM見積。読込中はVRAMを数えないため、見積で収容した集合が常駐へ揃った時点で上限を超えうる。
fn 見積vramバイト数() -> u64 {
    match チャンクメモリ量を見積もる(試験メタデータ()) {
        Ok(見積) => 見積.vramバイト数,
        Err(誤り) => panic!("試験用見積を作れなかった: {誤り}"),
    }
}

fn 退避一覧を取り出す(判定: &予算判定) -> (Vec<チャンク座標>, bool) {
    let 予算判定::使用量超過による退避 {
        退避一覧, 退避後も超過
    } = 判定
    else {
        panic!("上限を超えているのに使用量超過による退避にならなかった: {判定:?}");
    };
    (退避一覧.clone(), *退避後も超過)
}

#[test]
fn 上限を超えたら最も遠い常駐から退避して上限以下へ戻す() {
    let (パス一覧, カタログ, 目録) = 世界を作る("eviction_far", &[(0, 0), (1, 0), (2, 0)]);
    // 常駐2件は収まり3件は収まらない上限。3件目は先行2件が読込中でVRAMを数えないあいだに収容され、常駐へ揃った時点で超過する。
    let 上限 = ストリーミングメモリ量::生成する(100_000, 見積vramバイト数() * 3 - 1);
    let mut 調停 = 起動する(目録, 上限, 2);
    常駐まで進める(&mut 調停, &カタログ, 50.0, 3);

    let 退避フレーム = 進める(&mut 調停, &カタログ, 50.0);
    let (退避一覧, 退避後も超過) = 退避一覧を取り出す(退避フレーム.判定());
    assert_eq!(退避一覧, [チャンク座標::生成する(2, 0)]);
    assert!(!退避後も超過);
    assert_eq!(退避フレーム.gpu資源解除待ち一覧(), [チャンク座標::生成する(2, 0)]);
    assert_eq!(退避フレーム.読込開始一覧(), []);

    for 座標 in 退避フレーム.gpu資源解除待ち一覧() {
        assert!(調停.gpu資源の解除を報告する(*座標).is_ok());
    }
    // 解除が済むと使用量は上限以下へ戻り、退避した座標は見積のまま予算で除外されるため読み直しにならない。
    let 解除後 = 進める(&mut 調停, &カタログ, 50.0);
    assert!(解除後.使用量().vramバイト数 <= 上限.vramバイト数);
    assert_eq!(解除後.読込開始一覧(), []);
    assert_eq!(解除後.台帳登録数(), 2);
    後始末する(&パス一覧);
}

#[test]
fn 同距離の退避順は実行のたびに同じになる() {
    let 期待 = [チャンク座標::生成する(-1, 0), チャンク座標::生成する(1, 0)];
    for 回 in 0..2 {
        let (パス一覧, カタログ, 目録) = 世界を作る(&format!("eviction_tie{回}"), &[(0, 0), (-1, 0), (1, 0)]);
        // 常駐1件だけが収まる上限。中心を残したまま同距離2件を順に退避する。
        let 上限 = ストリーミングメモリ量::生成する(100_000, 見積vramバイト数() * 2 - 1);
        let mut 調停 = 起動する(目録, 上限, 1);
        常駐まで進める(&mut 調停, &カタログ, 50.0, 3);
        let (退避一覧, _) = 退避一覧を取り出す(進める(&mut 調停, &カタログ, 50.0).判定());
        assert_eq!(退避一覧, 期待);
        assert!(!退避一覧.contains(&チャンク座標::生成する(0, 0)));
        後始末する(&パス一覧);
    }
}

#[test]
fn 中心だけで上限を超えたら退避せず超過を報告し続ける() {
    let (パス一覧, カタログ, 目録) = 世界を作る("eviction_center", &[(0, 0)]);
    let 見積 = match チャンクメモリ量を見積もる(試験メタデータ()) {
        Ok(見積) => 見積,
        Err(誤り) => panic!("試験用見積を作れなかった: {誤り}"),
    };
    // 見積ちょうどの上限。読込が終わると実測が見積を上回るため、中心1件だけで上限を超える。
    let mut 調停 = 起動する(目録, ストリーミングメモリ量::生成する(見積.ramバイト数, 100_000), 1);
    let 準備完了一覧 = 準備完了を待つ(&mut 調停, &カタログ, 50.0, 1);
    assert_eq!(準備完了一覧, [チャンク座標::生成する(0, 0)]);

    for _回 in 0..3 {
        let 進行 = 進める(&mut 調停, &カタログ, 50.0);
        let (退避一覧, 退避後も超過) = 退避一覧を取り出す(進行.判定());
        assert_eq!(退避一覧, []);
        assert!(退避後も超過);
        assert_eq!(進行.台帳登録数(), 1);
        assert!(進行.使用量().ramバイト数 > 見積.ramバイト数);
    }

    // GPUへ載せるとCPUデータを手放すため、退避を経ずに上限以下へ戻る。
    let Ok(Some(_シーン)) = 調停.gpu転送のためにシーンデータを取り出す(チャンク座標::生成する(0, 0)) else {
        panic!("準備済みチャンクのシーンデータを取り出せなかった");
    };
    assert!(調停.gpu転送の完了を報告する(チャンク座標::生成する(0, 0)).is_ok());
    assert_eq!(進める(&mut 調停, &カタログ, 50.0).判定(), &予算判定::全件収容);
    後始末する(&パス一覧);
}
