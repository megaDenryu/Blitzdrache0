import type { タブ識別子 } from '../タブ識別子.ts'
import type { 編集領域ID } from './編集領域ID.ts'
import { タブ識別子から編集領域を見分ける } from './タブ識別子から編集領域を見分ける.ts'
import type { 編集領域の名乗り } from './編集領域の名乗り.ts'

// 編集領域ごとに「最後に前面だったタブ」を覚える台帳。タブの集合は全領域で共有するため、
// この記憶が分けるのは集合ではなく、領域を選び直したときにどのタブへ戻るかだけである。
export class 編集領域ごとの前面タブ記憶 {
    private readonly _領域ごとのタブ: Map<編集領域ID, タブ識別子> = new Map<編集領域ID, タブ識別子>()

    // 前面へ出たタブを、そのタブが属する領域の記憶として書き込む。どの領域にも属さないタブは覚えない。
    public 前面になったタブを覚える(タブ: タブ識別子): void {
        const 領域 = タブ識別子から編集領域を見分ける(タブ)
        if (領域 === null) return
        this._領域ごとのタブ.set(領域.識別子, タブ)
    }

    public 最後に前面だったタブを取り出す(領域: 編集領域の名乗り): タブ識別子 | null {
        return this._領域ごとのタブ.get(領域.識別子) ?? null
    }

    // 閉じたタブは二度と前面に出せないため、記憶から外す。
    public 閉じたタブを記憶から外す(タブ: タブ識別子): void {
        const 領域 = タブ識別子から編集領域を見分ける(タブ)
        if (領域 === null) return
        if (this._領域ごとのタブ.get(領域.識別子)?.綴り() === タブ.綴り()) {
            this._領域ごとのタブ.delete(領域.識別子)
        }
    }
}
