// 編集領域1つを指す安定識別子。数学DDDのbranded type(型レベルのみ、ランタイムコストゼロ)で
// stringと区別し、他の裸のstring(タブの綴り・アクティビティバーのラベル等)との取り違えを防ぐ。
// branded型はstringの部分型であるため、生のstringが要る場所(アクティビティIDへの昇格)へは
// 変換なしでそのまま渡せる。逆方向(検証されていないstring→編集領域ID)だけがこの生成関数を通る。
// 参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断12: 一番左のサイドバーが切り替えるのは編集領域である」
export type 編集領域ID = string & { readonly __brand: '編集領域ID' }

// 空文字はどの編集領域も指さない無効値であり、生成時に拒む(無言のデフォルト適用を避ける)。
export function 編集領域IDを生成する(綴り: string): 編集領域ID {
    if (綴り === '') throw new Error('編集領域IDは空文字を受け付けない')
    return 綴り as 編集領域ID
}
