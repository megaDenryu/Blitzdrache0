import type { タブ識別子 } from '../タブ識別子.ts'
import type { 編集領域ごとの前面タブ記憶 } from './編集領域ごとの前面タブ記憶.ts'
import type { 編集領域の名乗り } from './編集領域の名乗り.ts'

// タブが在るかを確かめ、前面へ出す操作だけを外殻から借りる口。
// 外殻レイアウトはこの2つのメソッドをそのまま持つため、そのまま渡せる。
export interface Iタブの選択操作 {
    タブが存在するか(綴り: string): boolean
    タブを選択する(綴り: string): void
}

// タブの選択操作と領域ごとの前面タブ記憶を保持し、編集領域を切り替えたときの前面タブの
// 出し入れを担う操作サービス。タブの集合そのものには触れない(タブは全領域で共有であり、
// 領域の切替でタブが開いたり閉じたりしてはならない)。
export class 編集領域切替サービス {
    public constructor(
        private readonly _タブの選択: Iタブの選択操作,
        private readonly _記憶: 編集領域ごとの前面タブ記憶,
    ) {}

    // 領域が選び直されたとき、その領域で最後に前面だったタブへ戻す。
    // 記憶が無いときと、記憶していたタブが既に閉じられているときは、前面をそのままにする。
    public 選ばれた領域の前面タブへ戻す(領域: 編集領域の名乗り): void {
        const タブ = this._記憶.最後に前面だったタブを取り出す(領域)
        if (タブ === null) return
        if (!this._タブの選択.タブが存在するか(タブ.綴り())) return
        this._タブの選択.タブを選択する(タブ.綴り())
    }

    public 前面になったタブを覚える(タブ: タブ識別子): void {
        this._記憶.前面になったタブを覚える(タブ)
    }

    public 閉じたタブを記憶から外す(タブ: タブ識別子): void {
        this._記憶.閉じたタブを記憶から外す(タブ)
    }
}
