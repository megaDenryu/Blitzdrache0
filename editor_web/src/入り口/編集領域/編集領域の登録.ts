import type { 領域エクスプローラー } from '../エクスプローラー/領域エクスプローラー.ts'
import type { 編集領域の名乗り } from './編集領域の名乗り.ts'

// 外殻が持つ編集領域1件の登録。名乗り(識別子・表示名・アイコンの文字)と、その領域の
// エクスプローラーを取り出す口を1件として束ねる。
// 中央のタブの管理はこの単位から独立させる。タブは全領域で共有するため、領域の登録が
// タブを持つと「領域ごとにタブの集合が分かれている」という誤った構造になるからである。
export class 編集領域の登録 {
    private constructor(
        public readonly 名乗り: 編集領域の名乗り,
        public readonly エクスプローラー: 領域エクスプローラー,
    ) {}

    public static 生成する(名乗り: 編集領域の名乗り, エクスプローラー: 領域エクスプローラー): 編集領域の登録 {
        return new 編集領域の登録(名乗り, エクスプローラー)
    }
}
