import { 編集領域IDを生成する, type 編集領域ID } from './編集領域ID.ts'

// 編集領域1つの見出し。アクティビティバーへ出すために要る識別子・表示名・アイコンの文字だけを持つ。
// エクスプローラーの実体を持たないため、画面の部品を読み込まずに領域の並びを検査できる。
// 編集領域とは、独立した探索と作業の文脈を持つ編集対象の集合のことである(資源の種別ごとではない)。
// 参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断12: 一番左のサイドバーが切り替えるのは編集領域である」
export class 編集領域の名乗り {
    private constructor(
        public readonly 識別子: 編集領域ID,
        public readonly 表示名: string,
        public readonly アイコンの文字: string,
    ) {}

    public static 生成する(識別子の綴り: string, 表示名: string, アイコンの文字: string): 編集領域の名乗り {
        if (表示名 === '') throw new Error('編集領域の表示名は空文字を受け付けない')
        if (アイコンの文字 === '') throw new Error('編集領域のアイコンの文字は空文字を受け付けない')
        return new 編集領域の名乗り(編集領域IDを生成する(識別子の綴り), 表示名, アイコンの文字)
    }
}

export const 世界の編集領域 = 編集領域の名乗り.生成する('world', '世界', '世')
export const 建物の編集領域 = 編集領域の名乗り.生成する('building', '建物', '建')
export const 楽曲の編集領域 = 編集領域の名乗り.生成する('song', '楽曲', '曲')

// アクティビティバーは並びの先頭を初期選択するため、この並びの先頭が起動時に選ばれる領域になる。
export const 編集領域の名乗り一覧: readonly 編集領域の名乗り[] = [世界の編集領域, 建物の編集領域, 楽曲の編集領域]

export const 起動時に選ばれる編集領域: 編集領域の名乗り = 世界の編集領域
