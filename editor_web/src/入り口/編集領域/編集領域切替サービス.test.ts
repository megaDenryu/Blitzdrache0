import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 建物定義IDを生成する } from '../../境界/index.ts'
import { タブ識別子 } from '../タブ識別子.ts'
import { 編集領域ごとの前面タブ記憶 } from './編集領域ごとの前面タブ記憶.ts'
import { 編集領域切替サービス, type Iタブの選択操作 } from './編集領域切替サービス.ts'
import { 世界の編集領域, 建物の編集領域, 楽曲の編集領域 } from './編集領域の名乗り.ts'

// 中央のタブ群の代役。開いているタブの集合と、前面へ出す要求の履歴だけを持つ。
// 存在しないタブを前面にしようとしたら投げるため、領域の切替が勝手にタブを開いていないかが分かる。
class 偽のタブ群 implements Iタブの選択操作 {
    public readonly 前面にした綴り一覧: string[] = []

    public constructor(private readonly _開いている綴り: Set<string>) {}

    public タブが存在するか(綴り: string): boolean {
        return this._開いている綴り.has(綴り)
    }

    public タブを選択する(綴り: string): void {
        if (!this._開いている綴り.has(綴り)) throw new Error(`開いていないタブを前面にしようとした: ${綴り}`)
        this.前面にした綴り一覧.push(綴り)
    }

    public 開いている綴りの並び(): string[] {
        return [...this._開いている綴り].sort()
    }
}

const 建物のタブ = タブ識別子.建物から生成する(建物定義IDを生成する('grid_building_1'))

function 世界と建物のタブを開いた状態を作る(): { タブ群: 偽のタブ群; 切替: 編集領域切替サービス } {
    const タブ群 = new 偽のタブ群(new Set([タブ識別子.大域世界().綴り(), 建物のタブ.綴り()]))
    const 記憶 = new 編集領域ごとの前面タブ記憶()
    const 切替 = new 編集領域切替サービス(タブ群, 記憶)
    切替.前面になったタブを覚える(タブ識別子.大域世界())
    切替.前面になったタブを覚える(建物のタブ)
    return { タブ群, 切替 }
}

describe('編集領域の切替', () => {
    it('領域を切り替えてもタブの集合が変わらないこと', () => {
        const { タブ群, 切替 } = 世界と建物のタブを開いた状態を作る()
        const 切替前 = タブ群.開いている綴りの並び()

        切替.選ばれた領域の前面タブへ戻す(世界の編集領域)
        切替.選ばれた領域の前面タブへ戻す(建物の編集領域)
        切替.選ばれた領域の前面タブへ戻す(楽曲の編集領域)

        assert.deepStrictEqual(タブ群.開いている綴りの並び(), 切替前)
    })

    it('領域を選び直すと、その領域で最後に前面だったタブへ戻ること', () => {
        const { タブ群, 切替 } = 世界と建物のタブを開いた状態を作る()

        切替.選ばれた領域の前面タブへ戻す(世界の編集領域)
        切替.選ばれた領域の前面タブへ戻す(建物の編集領域)

        assert.deepStrictEqual(タブ群.前面にした綴り一覧, [タブ識別子.大域世界().綴り(), 建物のタブ.綴り()])
    })

    it('一度も開いたことのない領域を選んでも、前面のタブを動かさないこと', () => {
        const { タブ群, 切替 } = 世界と建物のタブを開いた状態を作る()
        切替.選ばれた領域の前面タブへ戻す(楽曲の編集領域)
        assert.deepStrictEqual(タブ群.前面にした綴り一覧, [])
    })

    it('覚えていたタブが閉じられていたら、前面のタブを動かさないこと', () => {
        const { タブ群, 切替 } = 世界と建物のタブを開いた状態を作る()
        切替.閉じたタブを記憶から外す(建物のタブ)
        切替.選ばれた領域の前面タブへ戻す(建物の編集領域)
        assert.deepStrictEqual(タブ群.前面にした綴り一覧, [])
    })
})
