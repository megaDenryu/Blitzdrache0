import { タブ識別子 } from '../タブ識別子.ts'
import { 世界の編集領域, 建物の編集領域, 楽曲の編集領域, type 編集領域の名乗り } from './編集領域の名乗り.ts'

// 開いているタブがどの編集領域に属するかを見分ける純粋関数(自由関数の許容2条件(a): 依存も副作用も持たない)。
// タブは全領域で共有するため、どの領域から開いたかではなくタブの識別子そのものが所属を決める。
// どの領域にも属さないタブ(使い方)はnullを返す。使い方はアクティビティバー下部から開く
// 読み物であって編集対象ではないためである。
export function タブ識別子から編集領域を見分ける(タブ: タブ識別子): 編集領域の名乗り | null {
    if (タブ.チャンク座標を復元する() !== null) return 世界の編集領域
    if (タブ.建物定義IDを復元する() !== null) return 建物の編集領域
    if (タブ.楽曲IDを復元する() !== null) return 楽曲の編集領域

    const 綴り = タブ.綴り()
    if (綴り === タブ識別子.大域世界().綴り()) return 世界の編集領域
    if (綴り === タブ識別子.マテリアル().綴り()) return 世界の編集領域
    return null
}
