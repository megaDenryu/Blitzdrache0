import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 建物定義IDを生成する, 楽曲IDを生成する } from '../../境界/index.ts'
import { タブ識別子 } from '../タブ識別子.ts'
import { 編集領域ごとの前面タブ記憶 } from './編集領域ごとの前面タブ記憶.ts'
import { 世界の編集領域, 建物の編集領域, 楽曲の編集領域 } from './編集領域の名乗り.ts'

describe('編集領域ごとの前面タブ記憶', () => {
    it('何も覚えていないうちはどの領域もnullを返すこと', () => {
        const 記憶 = new 編集領域ごとの前面タブ記憶()
        assert.strictEqual(記憶.最後に前面だったタブを取り出す(世界の編集領域), null)
        assert.strictEqual(記憶.最後に前面だったタブを取り出す(建物の編集領域), null)
        assert.strictEqual(記憶.最後に前面だったタブを取り出す(楽曲の編集領域), null)
    })

    it('領域ごとに別々のタブを覚え、他の領域の記憶を上書きしないこと', () => {
        const 記憶 = new 編集領域ごとの前面タブ記憶()
        const 建物のタブ = タブ識別子.建物から生成する(建物定義IDを生成する('grid_building_1'))
        const 楽曲のタブ = タブ識別子.楽曲から生成する(楽曲IDを生成する('song-1'))

        記憶.前面になったタブを覚える(タブ識別子.チャンクから生成する({ x: 2, z: 3 }))
        記憶.前面になったタブを覚える(建物のタブ)
        記憶.前面になったタブを覚える(楽曲のタブ)

        assert.strictEqual(記憶.最後に前面だったタブを取り出す(世界の編集領域)?.綴り(), 'チャンク_2_3')
        assert.strictEqual(記憶.最後に前面だったタブを取り出す(建物の編集領域)?.綴り(), 建物のタブ.綴り())
        assert.strictEqual(記憶.最後に前面だったタブを取り出す(楽曲の編集領域)?.綴り(), 楽曲のタブ.綴り())
    })

    it('同じ領域のタブを続けて前面にすると、後のタブだけが残ること', () => {
        const 記憶 = new 編集領域ごとの前面タブ記憶()
        記憶.前面になったタブを覚える(タブ識別子.大域世界())
        記憶.前面になったタブを覚える(タブ識別子.マテリアル())
        assert.strictEqual(記憶.最後に前面だったタブを取り出す(世界の編集領域)?.綴り(), タブ識別子.マテリアル().綴り())
    })

    it('どの領域にも属さない使い方のタブは覚えないこと', () => {
        const 記憶 = new 編集領域ごとの前面タブ記憶()
        記憶.前面になったタブを覚える(タブ識別子.大域世界())
        記憶.前面になったタブを覚える(タブ識別子.使い方())
        assert.strictEqual(記憶.最後に前面だったタブを取り出す(世界の編集領域)?.綴り(), タブ識別子.大域世界().綴り())
    })

    it('覚えていたタブが閉じられたら記憶から外れること', () => {
        const 記憶 = new 編集領域ごとの前面タブ記憶()
        記憶.前面になったタブを覚える(タブ識別子.大域世界())
        記憶.閉じたタブを記憶から外す(タブ識別子.大域世界())
        assert.strictEqual(記憶.最後に前面だったタブを取り出す(世界の編集領域), null)
    })

    it('覚えていないほうのタブが閉じられても記憶は残ること', () => {
        const 記憶 = new 編集領域ごとの前面タブ記憶()
        記憶.前面になったタブを覚える(タブ識別子.大域世界())
        記憶.閉じたタブを記憶から外す(タブ識別子.マテリアル())
        assert.strictEqual(記憶.最後に前面だったタブを取り出す(世界の編集領域)?.綴り(), タブ識別子.大域世界().綴り())
    })
})
