import type { 外殻レイアウト } from 'VscodeShellLayout'
import { タブ識別子 } from '../タブ識別子.ts'
import { 編集領域IDを生成する, type 編集領域切替サービス, type 編集領域登録簿 } from '../編集領域/index.ts'
import { 使い方アクティビティID } from './シェルを構築する.ts'
import type { 建物の一覧サービス } from './建物の一覧サービス.ts'
import type { 楽曲の一覧サービス } from './楽曲の一覧サービス.ts'
import type { タブ開閉サービス } from './タブ開閉サービス.ts'

// シェルが出すタブとアクティビティバーの出来事を、タブ開閉サービスと編集領域切替サービスへ結ぶ工程。
// タブは全領域で共有するため、領域を選んでもタブの集合は変えず、その領域で最後に前面だった
// タブへ戻すだけにする(参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断12」)。
export function シェルの出来事をタブ開閉と領域切替へ結ぶ(
    シェル: 外殻レイアウト,
    登録簿: 編集領域登録簿,
    タブ開閉: タブ開閉サービス,
    領域切替: 編集領域切替サービス,
    建物の一覧: 建物の一覧サービス,
    楽曲の一覧: 楽曲の一覧サービス,
): void {
    シェル.onタブイベント({
        onタブ選択: (id) => {
            タブ開閉.タブ選択時処理(id)
            領域切替.前面になったタブを覚える(タブ識別子.綴りから復元する(id))
            void 建物の一覧.読み直す()
            void 楽曲の一覧.読み直す()
        },
        onタブ閉じる: (id) => {
            タブ開閉.タブを閉じたときの後処理(id)
            領域切替.閉じたタブを記憶から外す(タブ識別子.綴りから復元する(id))
        },
    })
    シェル.onアクティビティ選択((id) => {
        if (id === 使い方アクティビティID) {
            タブ開閉.使い方を開く()
            return
        }
        const 登録 = 登録簿.識別子から登録を取り出す(編集領域IDを生成する(id))
        if (登録 !== null) 領域切替.選ばれた領域の前面タブへ戻す(登録.名乗り)
    })
}
