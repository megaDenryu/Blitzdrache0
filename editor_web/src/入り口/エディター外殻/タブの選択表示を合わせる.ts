import type { エクスプローラーパネル } from '../エクスプローラー/index.ts'
import { タブ識別子 } from '../タブ識別子.ts'

// 前面へ出たタブの識別子から、エクスプローラーのどの項目を選択表示するかを決める工程
// (呼び出し連鎖の中の独立した工程。受け取るのはタブの識別子とエクスプローラー、返すのは無し)。
// タブ開閉サービスから分けるのは、タブを開く責務と、開いた結果を左サイドバーへ映す責務が別だからである。
export function タブの選択表示を合わせる(エクスプローラー: エクスプローラーパネル, タブID: string): void {
    if (タブID === タブ識別子.大域世界().綴り()) {
        エクスプローラー.大域世界を選択表示する()
        return
    }
    if (タブID === タブ識別子.マテリアル().綴り()) {
        エクスプローラー.マテリアルを選択表示する()
        return
    }
    if (タブID === タブ識別子.使い方().綴り()) {
        エクスプローラー.使い方を選択表示する()
        return
    }
    const 識別子 = タブ識別子.綴りから復元する(タブID)
    const 座標 = 識別子.チャンク座標を復元する()
    if (座標 !== null) {
        エクスプローラー.チャンクを選択表示する(座標)
        return
    }
    const 建物定義ID = 識別子.建物定義IDを復元する()
    if (建物定義ID !== null) エクスプローラー.建物を選択表示する(建物定義ID)
}
