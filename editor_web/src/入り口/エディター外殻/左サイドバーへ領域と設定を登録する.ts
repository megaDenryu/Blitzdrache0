import type { HtmlComponentBase } from 'sengen-ui'
import type { 外殻レイアウト } from 'VscodeShellLayout'
import type { 編集領域登録簿 } from '../編集領域/index.ts'
import { 使い方アクティビティID, 設定アクティビティID, 編集領域のアクティビティIDを作る } from './シェルを構築する.ts'

// アクティビティバー上部の3つの編集領域のエクスプローラーと、下部の設定パネルを左サイドバーへ
// 登録し、使い方を「左サイドバーを持たない項目」として登録する工程。
// 使い方は押すと中央へタブが1枚開くだけであり、左サイドバーの内容と開閉を変えない。
export function 左サイドバーへ領域と設定を登録する(
    シェル: 外殻レイアウト,
    登録簿: 編集領域登録簿,
    設定パネル: HtmlComponentBase,
): void {
    for (const 登録 of 登録簿.登録一覧) {
        シェル.左サイドバーへビューを登録する(編集領域のアクティビティIDを作る(登録.名乗り), 登録.エクスプローラー)
    }
    シェル.左サイドバーへビューを登録する(設定アクティビティID, 設定パネル)
    シェル.左サイドバーを持たない項目として登録する(使い方アクティビティID)
}
