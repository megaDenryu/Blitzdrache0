import type { 編集領域登録簿 } from '../編集領域/index.ts'
import type { 建物の一覧サービス } from './建物の一覧サービス.ts'
import type { 楽曲の一覧サービス } from './楽曲の一覧サービス.ts'
import type { タブ開閉サービス } from './タブ開閉サービス.ts'

// 3つの編集領域のエクスプローラーが出す「開く」「作る」の要求を、タブ開閉サービスと
// 建物・楽曲の一覧サービスへ結ぶ工程。領域ごとに配線の型が違うため、領域の数だけ結ぶ。
export function エクスプローラーの操作をタブへ結ぶ(
    登録簿: 編集領域登録簿,
    タブ開閉: タブ開閉サービス,
    建物の一覧: 建物の一覧サービス,
    楽曲の一覧: 楽曲の一覧サービス,
): void {
    登録簿.世界のエクスプローラー.配線する({
        on大域世界を開く: () => タブ開閉.大域世界を開く(),
        onチャンクを開く: (座標) => タブ開閉.チャンクを開く(座標),
        onマテリアルを開く: () => タブ開閉.マテリアルを開く(),
    })
    登録簿.建物のエクスプローラー.配線する({
        on建物を開く: (建物定義ID, 表示名) => タブ開閉.建物を開く(建物定義ID, 表示名),
        on建物を作る: () => void 建物の一覧.新しい建物を作る(),
    })
    登録簿.楽曲のエクスプローラー.配線する({
        on楽曲を開く: (楽曲ID, 表示名) => タブ開閉.楽曲を開く(楽曲ID, 表示名),
        on楽曲を作る: () => void 楽曲の一覧.新しい楽曲を作る(),
    })
}
