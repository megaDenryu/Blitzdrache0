import type { 外殻レイアウト } from 'VscodeShellLayout'

// 開いている文書の表示名が変わったことを受け取る口。楽曲編集ツールと建物編集ツールが同じ形の口を
// それぞれ宣言し、この1つの実装が両方の届け先になる。共通の型を1箇所へ置いて両ツールから参照させる
// ことはできない。層の向きが「入り口はツールルートを知ってよい」の一方向だからである。
export interface I文書の表示名の届け先 {
    表示名が変わった(新しい表示名: string): void
}

// 文書の表示名が変わったとき、その文書を開いているタブの見出しを同じ名前へ差し替える。
// 文書を開くたびに1件ずつ作り、受け持つタブの綴りを保持する。
// 保管庫から読み込んだ表示名も同じ知らせを通るため、開いた直後に見出しが保存済みの名前へ揃う。
export class タブ見出しを文書の表示名へ追随させる implements I文書の表示名の届け先 {
    public constructor(
        private readonly _シェル: 外殻レイアウト,
        private readonly _タブの綴り: string,
    ) {}

    public 表示名が変わった(新しい表示名: string): void {
        this._シェル.タブのラベルを変える(this._タブの綴り, 新しい表示名)
    }
}
