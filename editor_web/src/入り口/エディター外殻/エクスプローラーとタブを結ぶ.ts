import type { 外殻レイアウト } from 'VscodeShellLayout'
import type { エクスプローラーパネル } from '../エクスプローラー/index.ts'
import type { 建物の一覧サービス } from './建物の一覧サービス.ts'
import type { 楽曲の一覧サービス } from './楽曲の一覧サービス.ts'
import type { タブ開閉サービス } from './タブ開閉サービス.ts'

// エクスプローラーの項目とシェルのタブの出来事を、タブ開閉サービスと建物・楽曲の一覧サービスへ結ぶ工程。
export function エクスプローラーとタブを結ぶ(
    シェル: 外殻レイアウト,
    エクスプローラー: エクスプローラーパネル,
    タブ開閉: タブ開閉サービス,
    建物の一覧: 建物の一覧サービス,
    楽曲の一覧: 楽曲の一覧サービス,
): void {
    エクスプローラー.配線する({
        on大域世界を開く: () => タブ開閉.大域世界を開く(),
        onチャンクを開く: (座標) => タブ開閉.チャンクを開く(座標),
        onマテリアルを開く: () => タブ開閉.マテリアルを開く(),
        on使い方を開く: () => タブ開閉.使い方を開く(),
        on建物を開く: (建物定義ID, 表示名) => タブ開閉.建物を開く(建物定義ID, 表示名),
        on建物を作る: () => void 建物の一覧.新しい建物を作る(),
        on楽曲を開く: (名乗り, 表示名) => タブ開閉.楽曲を開く(名乗り, 表示名),
        on楽曲を作る: () => void 楽曲の一覧.新しい楽曲を作る(),
    })
    シェル.onタブイベント({
        onタブ選択: (id) => {
            タブ開閉.タブ選択時処理(id)
            void 建物の一覧.読み直す()
            void 楽曲の一覧.読み直す()
        },
        onタブ閉じる: (id) => タブ開閉.タブを閉じたときの後処理(id),
    })
}
