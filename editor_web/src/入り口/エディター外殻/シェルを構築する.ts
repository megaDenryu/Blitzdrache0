import { span, type DivC, type SpanC } from 'sengen-ui'
import { 外殻レイアウト, アクティビティID, 設定アイコン } from 'VscodeShellLayout'
import type { テーマ配色 } from '../../../submodules/VscodeShellLayout/src/テーマ/テーマ型.ts'
import { 編集領域の名乗り一覧, type 編集領域の名乗り } from '../編集領域/index.ts'

export const 設定アクティビティID = アクティビティID('settings')
export const 使い方アクティビティID = アクティビティID('guide')

// 編集領域の識別子をアクティビティバーの識別子へ昇格させる境界。編集領域IDはstringの部分型のため
// 変換なしで渡せる。この向きの変換をここ1箇所に閉じ、他所で綴りを組み立てない。
export function 編集領域のアクティビティIDを作る(名乗り: 編集領域の名乗り): アクティビティID {
    return アクティビティID(名乗り.識別子)
}

// アイコン用の資産をまだ持たないため、文字1つをアイコンとして描く。
function 文字のアイコンを作る(文字: string): (size: number, color: string) => SpanC {
    return (size, color) => span({ text: 文字 }).setStyleCSS({
        fontWeight: 'bold', fontSize: `${size * 0.8}px`, color,
        display: 'flex', alignItems: 'center', justifyContent: 'center', width: `${size}px`, height: `${size}px`,
    })
}

// エディター外殻のシェルレイアウト(アクティビティバー・左右サイドバー・下パネル・メニュー・
// ステータスバーの配置)を構築する。呼び出し元(エディター外殻)は初期テーマの配色と、
// 右サイドバーへ渡すインスペクタースロット・下パネルへ渡す棚のスロットを渡し、できあがったシェルを受け取る。
// アクティビティバーの上部は編集領域の切替であり、下部の設定と使い方は編集対象ではないため
// 領域の並びから外す(参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断12」)。
export function シェルを構築する(
    初期vsl配色: Partial<テーマ配色>,
    インスペクタースロット: DivC,
    下パネルスロット: DivC,
): 外殻レイアウト {
    return new 外殻レイアウト({
        テーマ: 初期vsl配色,
        タイトル: 'Blitzdrache0 エディター',
        アクティビティ項目一覧: 編集領域の名乗り一覧.map((名乗り) => ({
            id: 編集領域のアクティビティIDを作る(名乗り),
            ラベル: 名乗り.表示名,
            アイコン: 文字のアイコンを作る(名乗り.アイコンの文字),
        })),
        アクティビティバー下部項目一覧: [
            { id: 設定アクティビティID, ラベル: '設定', アイコン: (size, color) => 設定アイコン(size, color) },
            { id: 使い方アクティビティID, ラベル: '使い方', アイコン: 文字のアイコンを作る('?') },
        ],
        メニューバー表示: true,
        ステータスバー表示: true,
        ステータスバー右テキスト: 'Blitzdrache0 v0.1.0',
        // 下パネルは棚を持つツールを開いたときだけ現れる。パネル初期表示は「人が開いた状態で始めるか」の
        // 希望であり、開けてよい文脈かどうかは パネル利用可能 が持つ。棚を持つツールが1つも前面に
        // 無いあいだは利用不可のままで、パネルもそのスプリッターも画面へ出ない(判断14)。
        パネル初期表示: true,
        パネル利用可能: false,
        パネル内容: 下パネルスロット,
        右サイドバー有効: true,
        右サイドバー内容: インスペクタースロット,
        // 260px既定だとインスペクターの見出し・バッジ・モード切替ボタンが折れずに収まらない。
        // 各パネルのラベル幅実測から280pxへ広げる(参照: 是正の規律)。
        右サイドバー既定幅: 280,
        // 48px幅のアクティビティバーに日本語ラベルを常時表示すると任意の文字位置で折り返される。
        // VSCode本家と同じくアイコン+ツールチップのみにする。
        アクティビティバーラベルを常に隠す: true,
    })
}
