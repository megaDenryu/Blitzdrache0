import type { HtmlComponentBase } from 'sengen-ui'
import type { タブ識別子 } from '../タブ識別子.ts'

// 編集領域1つの探索を担う左サイドバーの内容が満たす契約。
// 外殻はこの契約だけを見て領域を切り替えるため、どの領域が何を並べているかを知らない。
// 選択表示の解除と反映を2つのメソッドに分けるのは、タブが全領域で共有であり、
// 前面のタブが移ったときに「他の領域の選択表示も消す」必要があるからである。
export interface 領域エクスプローラー extends HtmlComponentBase {
    // 前面へ出たタブが自分の領域の対象なら、対応する項目を選択表示する。対象でなければ何もしない。
    前面のタブに合わせて選択表示する(タブ: タブ識別子): void
    選択表示を解除する(): void
}
