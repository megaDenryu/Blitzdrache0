export type 起動時タブ種別 = '大域世界' | '使い方'

// 起動直後に開くタブの並びを決める。並びの末尾が起動直後に前面へ来るタブになるため、
// 使い方ガイドを見せたいときは大域世界の後ろへ積む。
// この判定を大域世界を開く処理の実行結果から切り離すことで、起動シーケンスの途中経過に
// 依存せず「未閲覧なら使い方ガイドを前面にする」という決定だけで並びが決まる。
export function 起動時タブ計画を立てる(使い方ガイド閲覧済みか: boolean): readonly 起動時タブ種別[] {
    return 使い方ガイド閲覧済みか ? ['大域世界'] : ['大域世界', '使い方']
}
