import type { プロジェクト保管庫接続 } from '../../境界/通信/index.ts'
import { ワールド編集状態 } from '../ワールド/編集モデル/index.ts'
import { 初期大域ワールド状態を生成する } from './初期大域ワールド生成.ts'

// 大域グリッドエディターの編集状態と保管庫の間で相互変換と保存・読込を行う。
export async function 大域ワールド状態を保管庫から読み込む(
    保管庫: プロジェクト保管庫接続,
): Promise<{ 状態: ワールド編集状態; 結果種別: '読込成功' | '初期生成' }> {
    const 大域構造結果 = await 保管庫.大域世界の構造を読む()
    if (大域構造結果.種別 === '失敗') {
        throw new Error(`大域世界構造の読込に失敗した: ${大域構造結果.エラー.種別} ${大域構造結果.エラー.説明}`)
    }
    if (大域構造結果.種別 === '無し') {
        return { 状態: 初期大域ワールド状態を生成する(), 結果種別: '初期生成' }
    }

    const 大域高さ結果 = await 保管庫.大域世界の高さ格子を読む()
    if (大域高さ結果.種別 === '失敗') {
        throw new Error(`大域世界高さ格子の読込に失敗した: ${大域高さ結果.エラー.種別} ${大域高さ結果.エラー.説明}`)
    }

    const 大域高さ = 大域高さ結果.種別 === '成功' ? new Float32Array(大域高さ結果.値) : undefined
    const 状態 = new ワールド編集状態(大域構造結果.値, 大域高さ)
    return { 状態, 結果種別: '読込成功' }
}

export async function 大域ワールド状態を保管庫へ保存する(
    保管庫: プロジェクト保管庫接続,
    状態: ワールド編集状態,
): Promise<void> {
    const 大域構造保存 = await 保管庫.大域世界の構造を保存する(状態.大域世界構造)
    if (大域構造保存.種別 === '失敗') {
        throw new Error(`大域世界構造の保存に失敗した: ${大域構造保存.エラー.種別} ${大域構造保存.エラー.説明}`)
    }

    const 大域高さ保存 = await 保管庫.大域世界の高さ格子を保存する(状態.大域高さ場.格子データ.buffer)
    if (大域高さ保存.種別 === '失敗') {
        throw new Error(`大域世界高さ格子の保存に失敗した: ${大域高さ保存.エラー.種別} ${大域高さ保存.エラー.説明}`)
    }
}
