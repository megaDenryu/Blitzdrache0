// 大域編集ツールで選択可能な4つの編集操作モード。
export type 大域編集モード = '選択' | '大域造成' | '広域道路作成' | '広域道路編集'

export const 大域編集モード一覧: readonly 大域編集モード[] = [
    '選択',
    '大域造成',
    '広域道路作成',
    '広域道路編集',
] as const

// 道路点マーカーを画面に出すモード。他のモードでは触れない物体が浮いて見えるため隠す。
export function 広域道路の点を扱うモードか(モード: 大域編集モード): boolean {
    return モード === '広域道路作成' || モード === '広域道路編集'
}
