import { 場面を作る, 透視カメラを作る, 環境光を作る, 平行光源を作る } from 'SengenThree'
import { ワールド編集状態, 地表材質 } from '../../../../チャンク編集/編集モデル/index.ts'
import { 地形メッシュ部品 } from '../../../../チャンク編集/画面/三次元/地形/地形メッシュ部品.ts'
import { ブラシリング部品 } from '../../../../チャンク編集/画面/三次元/ブラシ/ブラシリング部品.ts'
import { 道路帯メッシュ部品 } from '../../../../チャンク編集/画面/三次元/道路/道路帯メッシュ部品.ts'
import { 道路点マーカー部品 } from '../../../../チャンク編集/画面/三次元/道路/道路点マーカー部品.ts'
import { 軌道カメラ制御器 } from '../../../../チャンク編集/画面/三次元/カメラ/軌道カメラ制御器.ts'
import { 地形追従カメラ制御器 } from '../../../../チャンク編集/画面/三次元/カメラ/地形追従カメラ制御器.ts'
import { 注視点マーカー部品 } from '../../../../チャンク編集/画面/三次元/カメラ/注視点マーカー部品.ts'
import { 毎フレーム処理の束 } from '../../../../チャンク編集/画面/三次元/毎フレーム処理の束.ts'
import { 既定の三次元の配色を作る } from '../../../../チャンク編集/画面/三次元/三次元の配色.ts'
import { チャンク境界格子部品 } from '../チャンク境界格子部品.ts'

export interface 大域シーン部品束 {
    readonly 場面: ReturnType<typeof 場面を作る>
    readonly カメラ: ReturnType<typeof 透視カメラを作る>
    readonly カメラ制御: 地形追従カメラ制御器
    readonly 地形: 地形メッシュ部品
    readonly チャンク境界: チャンク境界格子部品
    readonly ブラシリング: ブラシリング部品
    readonly 注視点マーカー: 注視点マーカー部品
    readonly 道路帯: 道路帯メッシュ部品
    readonly 道路点マーカー: 道路点マーカー部品
    readonly 毎フレーム処理: 毎フレーム処理の束
}

// 大域編集ビューの三次元シーングラフを構築する。呼び出し元(大域三次元ビュー部品)は
// キャンバス・描画ループ・破棄の管理だけを担い、シーンの内訳の組み立てはここへ閉じる。
export function 大域シーンを構築する(編集状態: ワールド編集状態, 初期背景色: string | number): 大域シーン部品束 {
    const 地表材質モデル = new 地表材質(編集状態.大域高さ場.解像度, 編集状態.大域高さ場.一辺のメートル)
    const 既定配色 = 既定の三次元の配色を作る()
    const 地形 = new 地形メッシュ部品(編集状態.大域高さ場, 地表材質モデル, {
        低色: 既定配色.標高低色,
        中色: 既定配色.標高中色,
        高色: 既定配色.標高高色,
    })
    const チャンク境界 = new チャンク境界格子部品(
        編集状態.区画割り.一辺のメートル,
        編集状態.区画割り.軸あたりチャンク数,
    )
    const ブラシリング = new ブラシリング部品(編集状態.大域高さ場)
    const 道路帯 = new 道路帯メッシュ部品(既定配色.道路色)

    const カメラ = 透視カメラを作る({ 画角: 50, アスペクト比: 16 / 9, 奥クリップ距離: 5000 })
    const 道路点マーカー = new 道路点マーカー部品(カメラ, 既定配色.道路点マーカー配色)
    const カメラ制御 = new 地形追従カメラ制御器(new 軌道カメラ制御器(カメラ, 800, 20, 3000), 編集状態.大域高さ場)
    const 注視点マーカー = new 注視点マーカー部品(カメラ)

    const 場面 = 場面を作る()
        .背景色を設定する(初期背景色)
        .childs([
            カメラ,
            環境光を作る({ 色: 0xe2e8f0, 強さ: 0.5 }),
            平行光源を作る({ 色: 0xffedd5, 強さ: 1.2 }).位置を設定する(400, 800, 300),
            地形,
            チャンク境界,
            ブラシリング,
            注視点マーカー,
            道路帯,
            道路点マーカー,
        ])

    const 毎フレーム処理 = new 毎フレーム処理の束()
    毎フレーム処理.加える(() => 道路点マーカー.見かけの大きさを更新する())

    return { 場面, カメラ, カメラ制御, 地形, チャンク境界, ブラシリング, 注視点マーカー, 道路帯, 道路点マーカー, 毎フレーム処理 }
}
