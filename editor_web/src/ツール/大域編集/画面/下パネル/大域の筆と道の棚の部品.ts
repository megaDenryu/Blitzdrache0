import { 道を引き始めるパネル } from '../../../チャンク編集/画面/パネル/共通/道を引き始めるパネル.ts'
import type { 大域編集モード } from '../パネル/モード切替/大域モード定義.ts'
import { 大域造成パネル } from '../パネル/造成/大域造成パネル.ts'
import { 大域のモードの案内札 } from './大域のモードの案内札.ts'
import { 大域造成の筆の初期値 } from './大域の筆の初期値.ts'

// 大域の筆と道の棚が集約する部品の型契約(部品DTO)。ここに並ぶのはすべて「これから使うもの」であり、
// 選んでいる道の設定と書き出しは右サイドバーのインスペクターが持つ(設計正本の判断14)。
export class 大域の筆と道の棚の部品 {
    private constructor(
        public readonly 案内: 大域のモードの案内札,
        public readonly 大域の筆: 大域造成パネル,
        public readonly 道を引き始める: 道を引き始めるパネル,
    ) {}

    // 筆の初期値は編集状態と同じ1箇所から取る。人が触る前の棚の表示と、実際に筆が使う値が
    // ずれていると、表示が正本と一致しない(判断6)。
    public static 作る(初期モード: 大域編集モード): 大域の筆と道の棚の部品 {
        return new 大域の筆と道の棚の部品(
            new 大域のモードの案内札(初期モード),
            new 大域造成パネル(大域造成の筆の初期値.種別, 大域造成の筆の初期値.半径メートル, 大域造成の筆の初期値.強さ),
            new 道を引き始めるパネル(),
        )
    }

    public delete(): void {
        this.案内.delete()
        this.大域の筆.delete()
        this.道を引き始める.delete()
    }
}
