import type { ポインタ事象情報 } from 'SengenThree'
import type { 道路点クリックハンドラ } from '../チャンク編集/道路点クリックハンドラ.ts'
import type { 大域編集画面部品 } from './画面/index.ts'
import type { 大域編集状態 } from './大域編集状態.ts'

// 広域道路の点の追加・分岐・選択・挿入のクリック入力を、モードによって振り分ける。
// 道路点まわりの手順そのものはチャンク編集と共有の道路点クリックハンドラが持つ。
export class 大域編集クリックハンドラ {
    public constructor(
        private readonly _状態: 大域編集状態,
        private readonly _部品: 大域編集画面部品,
        private readonly _道路点: 道路点クリックハンドラ,
    ) {}

    public クリック処理(事象: ポインタ事象情報): void {
        if (this._状態.モード === '広域道路作成') {
            this._道を描く(事象)
            return
        }

        if (this._状態.モード === '広域道路編集') {
            // 点の上のクリックは選択を優先し、点に当たらず帯の上だったときだけ点を割り込ませる。
            if (!this._道路点.道路点を選択する(事象.当たり一覧)) {
                this._道路点.帯の上へ挿入する(事象.当たり一覧)
            }
        }
    }

    // 既存の点の上なら分岐を始め、地形の上なら描き足す。地形のダブルクリックは、
    // 2回目のクリックで点を足さずに道を終え、次のクリックから新しい道を始める合図にする。
    private _道を描く(事象: ポインタ事象情報): void {
        if (this._道路点.分岐を始める(事象.当たり一覧)) return
        const 最前面当たり = 事象.最前面当たり
        if (最前面当たり === null || 最前面当たり.部品 !== this._部品.三次元ビュー.地形) return
        if (事象.原初事象.detail >= 2) {
            this._道路点.次のクリックから新しい道にする()
            return
        }
        const 交差点 = 最前面当たり.交差点
        this._道路点.描き足す({ x: 交差点.x, y: 交差点.y, z: 交差点.z })
    }
}
