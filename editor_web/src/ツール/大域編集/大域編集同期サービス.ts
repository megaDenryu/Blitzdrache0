import type { ワールド編集状態 } from '../チャンク編集/編集モデル/index.ts'
import type { 大域編集画面部品 } from './画面/index.ts'
import type { 大域編集状態 } from './大域編集状態.ts'
import { 広域道路の点を扱うモードか } from './画面/パネル/モード切替/大域モード定義.ts'
import { 居なくなった道路と道路点の選択を外す } from '../チャンク編集/選択中の道路点の後始末.ts'

// 大域編集モデルの状態変化を三次元描画部品および3つの区画(エディタ領域の操作帯・下パネルの棚・
// 右サイドバーのインスペクター)へ一括同期する。
export class 大域編集同期サービス {
    public constructor(
        private readonly _モデル: ワールド編集状態,
        private readonly _UI状態: 大域編集状態,
        private readonly _部品: 大域編集画面部品,
    ) {}

    public 全体を同期する(): void {
        this.地形を同期する()
        this.道路を同期する()
        this.UIを同期する()
    }

    public 地形を同期する(): void {
        this._部品.三次元ビュー.地形.高さ場を更新する(this._モデル.大域高さ場)
    }

    public 道路を同期する(): void {
        const 道路一覧 = this._モデル.広域道路一覧
        居なくなった道路と道路点の選択を外す(this._UI状態, 道路一覧)
        this._部品.三次元ビュー.道路帯.更新する(道路一覧, this._モデル.大域高さ場)
        this._部品.三次元ビュー.道路点マーカー.更新する(道路一覧, {
            選択中の道路点: this._UI状態.選択中の道路点,
            つかんでいる道路点: this._UI状態.つかんでいる道路点,
            アクティブな道路の添字: this._UI状態.アクティブな道路の添字,
        })
    }

    public UIを同期する(): void {
        this._部品.三次元ビュー.道路点マーカー.表示するか設定する(広域道路の点を扱うモードか(this._UI状態.モード))
        this._部品.操作帯.表示を更新する(this._UI状態.モード, this._UI状態.取り消し履歴スタック.length > 0)
        this._部品.棚.モードの案内を更新する(this._UI状態.モード)
        this._部品.インスペクター.部品.道路.選択中の道路点があるか設定する(this._UI状態.選択中の道路点 !== null)
        const 道路一覧 = this._モデル.広域道路一覧
        const 添字 = this._UI状態.アクティブな道路の添字
        const 設定 = 添字 !== null && 道路一覧.道路が在るか(添字) ? 道路一覧.道路を取り出す(添字) : null
        this._部品.インスペクター.部品.道路.対象の道を設定する(添字, 道路一覧.件数, 設定)
    }
}
