import type { プロジェクト保管庫接続 } from '../../境界/通信/index.ts'
import { 保存状態サービス } from '../../境界/通信/index.ts'
import type { ワールド編集状態 } from '../チャンク編集/編集モデル/index.ts'
import type { 大域永続化パネル } from './画面/パネル/永続化/index.ts'
import type { 大域編集同期サービス } from './大域編集同期サービス.ts'
import { 大域ワールド状態を保管庫から読み込む, 大域ワールド状態を保管庫へ保存する } from './大域編集永続化.ts'

// 大域永続化パネルの保存・読み込みボタンと保管庫通信を配線する。
export function 大域永続化イベントを配線する(
    パネル: 大域永続化パネル,
    保管庫: プロジェクト保管庫接続,
    モデル: ワールド編集状態,
    同期: 大域編集同期サービス,
): () => void {
    let 購読解除 = (): void => {}
    if ('通知' in 保管庫 && 保管庫.通知 instanceof 保存状態サービス) {
        購読解除 = 保管庫.通知.大域状態を購読する((状態) => {
            パネル.状態文言を更新する(状態.文言, 状態.エラーか)
        })
    }

    パネル.on保存クリック(() => {
        パネル.ボタン活性状態を更新する(false)
        パネル.状態文言を更新する('保存中...', false)
        大域ワールド状態を保管庫へ保存する(保管庫, モデル)
            .then(() => {
                パネル.状態文言を更新する('保存完了', false)
            })
            .catch((原因: unknown) => {
                const メッセージ = 原因 instanceof Error ? 原因.message : String(原因)
                パネル.状態文言を更新する(`保存失敗: ${メッセージ}`, true)
            })
            .finally(() => {
                パネル.ボタン活性状態を更新する(true)
            })
    })

    パネル.on読込クリック(() => {
        パネル.ボタン活性状態を更新する(false)
        パネル.状態文言を更新する('読み込み中...', false)
        大域ワールド状態を保管庫から読み込む(保管庫)
            .then((結果) => {
                モデル.状態を上書きする(結果.状態)
                同期.全体を同期する()
                const 表示 = 結果.結果種別 === '読込成功' ? '読み込み完了' : '初期大域ワールド生成'
                パネル.状態文言を更新する(表示, false)
            })
            .catch((原因: unknown) => {
                const メッセージ = 原因 instanceof Error ? 原因.message : String(原因)
                パネル.状態文言を更新する(`読込失敗: ${メッセージ}`, true)
            })
            .finally(() => {
                パネル.ボタン活性状態を更新する(true)
            })
    })

    return 購読解除
}

export async function 起動時に大域ワールドを読み込む(
    パネル: 大域永続化パネル,
    保管庫: プロジェクト保管庫接続,
    モデル: ワールド編集状態,
    同期: 大域編集同期サービス,
): Promise<void> {
    try {
        const 結果 = await 大域ワールド状態を保管庫から読み込む(保管庫)
        if (結果.結果種別 === '読込成功') {
            モデル.状態を上書きする(結果.状態)
            同期.全体を同期する()
            パネル.状態文言を更新する('読込完了(起動時)', false)
        } else {
            パネル.状態文言を更新する('未保存(初期生成)', false)
        }
    } catch (原因: unknown) {
        const メッセージ = 原因 instanceof Error ? 原因.message : String(原因)
        パネル.状態文言を更新する(`起動時読込失敗: ${メッセージ}`, true)
    }
}
