import { カメラ操作適用器 } from '../チャンク編集/画面/三次元/カメラ/カメラ操作適用器.ts'
import { ホイールと右クリックを配線する } from '../チャンク編集/画面/三次元/カメラ/ホイールと右クリックを配線する.ts'

// 広域道路の点は大域地形へ置くと帯が地面へ埋もれるため、この高さだけ持ち上げて置く。
const 広域道路の点を持ち上げるメートル = 0.5

// 大域三次元ビューのポインタ操作およびレイキャスト入力を配線する。
// キーボード入力(取り消し・WASDQE移動・Altのモード循環)はチャンク編集ツールと共有する
// 画面/三次元/カメラ/キーボード配線.ts が持つ。
export function 大域ポインタとキー入力を配線する(
    部品: 大域編集画面部品,
    状態: 大域編集状態,
    操作: 大域編集操作サービス,
    同期: 大域編集同期サービス,
    モデル: ワールド編集状態,
): () => void {
    const ビュー = 部品.三次元ビュー
    const 押下 = new ポインタ押下状態()
    const 道路一覧 = new 編集対象の道路一覧(モデル, { 種類: '広域' })
    const 筆致 = new 大域編集筆致ハンドラ(モデル, 状態, 部品, 同期)
    const 道路点クリック = new 道路点クリックハンドラ(道路一覧, 状態, ビュー, 操作, 同期, 広域道路の点を持ち上げるメートル)
    const 道路点ドラッグ = new 道路点ドラッグハンドラ(道路一覧, 状態, ビュー, 操作, 同期)
    const 振り分け = new 大域編集ポインタ振り分け(状態, ビュー.地形, 道路点クリック, 道路点ドラッグ)
    const カメラ操作 = new カメラ操作適用器(ビュー)

    // 帯は広域道路編集モードのときだけ当たり判定へ入れる。常時入れると、大域造成で道路の上を
    // なぞったときに地形より手前の帯が拾われて筆が止まる。
    // 広域道路作成モードでは、既存の点をクリックして分岐を始められるようマーカーだけを入れる。
    function レイキャストの対象部品一覧を決める(): readonly 三次元部品[] {
        if (状態.モード === '広域道路編集') return [ビュー.地形, ビュー.道路点マーカー, ビュー.道路帯]
        if (状態.モード === '広域道路作成') return [ビュー.地形, ビュー.道路点マーカー]
        return [ビュー.地形]
    }

    // 統一操作規則: 右・中は全モードで常にカメラ、左はそのモードの主作業。
    const 移動時 = ({ 当たり一覧, 最前面当たり, 原初事象 }: ポインタ事象情報): void => {
        const 移動量 = 押下.移動量を取り出す(原初事象)
        const ボタン = 押下.押しているボタン
        if (ボタン !== null && カメラ操作.試みる(ポインタ操作の割り当てを決める(ボタン), 移動量.横, 移動量.縦)) return
        if (振り分け.動かされた(当たり一覧)) return
        if (最前面当たり !== null && 最前面当たり.部品 === ビュー.地形) {
            筆致.移動時(最前面当たり.交差点, 押下.左ボタン押下中, 原初事象.shiftKey)
        } else {
            ビュー.ブラシリング.可視性を設定する(false)
        }
    }

    ビュー.レイキャスト.配線する({
        移動時,
        押し時: ({ 当たり一覧, 原初事象 }) => {
            押下.押された(原初事象)
            if (振り分け.押された(原初事象.button, 当たり一覧)) return
            筆致.押し時(原初事象.button)
        },
        離し時: ({ 原初事象 }) => {
            押下.離された(原初事象)
            振り分け.離された(原初事象.button)
            筆致.離し時(原初事象.button)
        },
        クリック時: (事象) => 振り分け.クリックされた(事象),
    })

    ビュー.レイキャスト.キャンバスの購読を開始する({
        キャンバス: ビュー.キャンバス要素.dom.element,
        カメラ: ビュー.カメラ,
        対象部品一覧: レイキャストの対象部品一覧を決める,
    })

    const ホイールと右クリックの解除 = ホイールと右クリックを配線する(ビュー)

    const キーボード解除 = キーボード入力を配線する(部品, 状態, 操作, 同期, 大域編集モード一覧)

    return () => {
        ビュー.レイキャスト.キャンバスの購読を解除する()
        ホイールと右クリックの解除()
        キーボード解除()
    }
}
