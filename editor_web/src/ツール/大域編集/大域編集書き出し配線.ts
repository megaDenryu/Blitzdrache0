import type { ソースアセット書き出し接続 } from '../../境界/通信/index.ts'
import type { スライス仕様パネル } from './画面/パネル/スライス/index.ts'

// スライス仕様パネルの書き出しボタンとソースアセット書き出し接続を配線する。
// 書き出しは保管庫に保存済みの大域世界を対象にする明示操作であり、編集モデルは読まない
// (未保存なら保存前提が破れた422がそのまま画面へ出る)。
export function 大域書き出しイベントを配線する(
    パネル: スライス仕様パネル,
    書き出し接続: ソースアセット書き出し接続,
): void {
    パネル.配線する({
        on書き出しクリック: (世界名) => {
            パネル.ボタン活性状態を更新する(false)
            パネル.状態文言を更新する('書き出し中...', false)
            書き出し接続.ソースアセットへ書き出す(世界名)
                .then((結果) => {
                    if (結果.種別 === '成功') {
                        パネル.状態文言を更新する(`${結果.書いたファイル数}件のファイルを${結果.出力先}へ書き出した`, false)
                    } else {
                        パネル.状態文言を更新する(`書き出し失敗: ${結果.エラー.種別} ${結果.エラー.説明}`, true)
                    }
                })
                .catch((原因: unknown) => {
                    const メッセージ = 原因 instanceof Error ? 原因.message : String(原因)
                    パネル.状態文言を更新する(`書き出し失敗: ${メッセージ}`, true)
                })
                .finally(() => {
                    パネル.ボタン活性状態を更新する(true)
                })
        },
    })
}
