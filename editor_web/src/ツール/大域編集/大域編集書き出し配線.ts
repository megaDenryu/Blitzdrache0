import type { ソースアセット書き出し接続 } from '../../境界/通信/index.ts'
import type { スライス仕様パネル } from './画面/パネル/スライス/index.ts'
import { パネル操作を実行する, type パネル操作結果 } from '../チャンク編集/永続化パネル操作.ts'

// スライス仕様パネルの書き出しボタンとソースアセット書き出し接続を配線する。
// 書き出しは保管庫に保存済みの大域世界を対象にする明示操作であり、編集モデルは読まない
// (未保存なら保存前提が破れた422がそのまま画面へ出る)。
export function 大域書き出しイベントを配線する(
    パネル: スライス仕様パネル,
    書き出し接続: ソースアセット書き出し接続,
): void {
    const 書き出す = (世界名: string) => async (): Promise<パネル操作結果> => {
        const 結果 = await 書き出し接続.ソースアセットへ書き出す(世界名)
        if (結果.種別 === '成功') {
            return { 文言: `${結果.書いたファイル数}件のファイルを${結果.出力先}へ書き出した`, エラーか: false }
        }
        return { 文言: `書き出し失敗: ${結果.エラー.種別} ${結果.エラー.説明}`, エラーか: true }
    }

    パネル.配線する({
        on書き出しクリック: (世界名) => {
            void パネル操作を実行する(パネル, '書き出し中...', 書き出す(世界名), '書き出し失敗')
        },
    })
}
