import type { ワールド編集状態 } from '../チャンク編集/編集モデル/index.ts'
import type { 大域編集画面部品 } from './画面/index.ts'
import type { 大域編集状態 } from './大域編集状態.ts'
import type { 大域編集操作サービス } from './大域編集操作サービス.ts'
import type { 大域編集同期サービス } from './大域編集同期サービス.ts'

// 大域UIパネル群と操作サービス・同期サービスを配線ポート経由で接続する。
export function 大域パネルイベントを配線する(
    部品: 大域編集画面部品,
    状態: 大域編集状態,
    操作: 大域編集操作サービス,
    同期: 大域編集同期サービス,
    モデル: ワールド編集状態,
): void {
    部品.インスペクター.部品.モード切替.配線する({
        onモード変更: (モード) => {
            状態.モード = モード
            同期.UIを同期する()
        },
        on地形追従変更: (有効) => {
            部品.三次元ビュー.カメラ制御.地形追従を設定する(有効)
        },
    })
    部品.インスペクター.部品.造成.配線する({
        on筆致種別変更: (種別) => {
            状態.造成筆致種別 = 種別
        },
        on半径変更: (半径) => {
            状態.造成半径 = 半径
        },
        on強さ変更: (強さ) => {
            状態.造成強さ = 強さ
        },
    })
    部品.インスペクター.部品.道路.配線する({
        on全幅変更: (全幅) => {
            モデル.広域道路.全幅メートル = 全幅
            状態.道路全幅 = 全幅
            同期.道路を同期する()
        },
        on細分割数変更: (細分割) => {
            モデル.広域道路.細分割数 = 細分割
            状態.道路細分割数 = 細分割
            同期.道路を同期する()
        },
        on選択ノード削除: () => {
            if (状態.選択中ノード添字 !== null) {
                操作.コマンドを実行する({
                    種類: '道路点を削除する',
                    値: {
                        対象: { 種類: '広域' },
                        添字: 状態.選択中ノード添字,
                    },
                })
                状態.選択中ノード添字 = null
                同期.道路を同期する()
                同期.UIを同期する()
            }
        },
        on道路リセット: () => {
            操作.道路を全消去する()
        },
    })
}
