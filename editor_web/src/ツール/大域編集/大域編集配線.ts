import { 編集対象の道路一覧 } from '../チャンク編集/編集モデル/index.ts'
import type { ワールド編集状態 } from '../チャンク編集/編集モデル/index.ts'
import { 道路パネル操作 } from '../チャンク編集/道路パネル操作.ts'
import type { 大域編集画面部品 } from './画面/index.ts'
import type { 大域編集状態 } from './大域編集状態.ts'
import type { 大域編集操作サービス } from './大域編集操作サービス.ts'
import type { 大域編集同期サービス } from './大域編集同期サービス.ts'

// 大域UIパネル群と操作サービス・同期サービスを配線ポート経由で接続する。
export function 大域パネルイベントを配線する(
    部品: 大域編集画面部品,
    状態: 大域編集状態,
    操作: 大域編集操作サービス,
    同期: 大域編集同期サービス,
    モデル: ワールド編集状態,
): void {
    const 道路一覧 = new 編集対象の道路一覧(モデル, { 種類: '広域' })
    const パネル操作 = new 道路パネル操作(道路一覧, 状態, 操作, 同期)

    // 対象の道が無いときスライダーは操作できないため、この関数が呼ばれるのは道が在るときだけである。
    const 対象の道へ = (設定を書き換える: (道路: ReturnType<typeof 道路一覧.道路を取り出す>) => void): void => {
        const 添字 = 状態.アクティブな道路の添字
        if (添字 === null || !道路一覧.一覧.道路が在るか(添字)) return
        設定を書き換える(道路一覧.道路を取り出す(添字))
    }

    部品.インスペクター.部品.モード切替.配線する({
        onモード変更: (モード) => {
            状態.モード = モード
            同期.UIを同期する()
        },
        on地形追従変更: (有効) => {
            部品.三次元ビュー.カメラ制御.地形追従を設定する(有効)
        },
    })
    部品.インスペクター.部品.造成.配線する({
        on筆致種別変更: (種別) => {
            状態.造成筆致種別 = 種別
        },
        on半径変更: (半径) => {
            状態.造成半径 = 半径
        },
        on強さ変更: (強さ) => {
            状態.造成強さ = 強さ
        },
    })
    部品.インスペクター.部品.道路.配線する({
        on全幅変更: (全幅) => {
            対象の道へ((道路) => { 道路.全幅メートル = 全幅 })
            同期.道路を同期する()
        },
        on細分割数変更: (細分割) => {
            対象の道へ((道路) => { 道路.細分割数 = 細分割 })
            同期.道路を同期する()
        },
        on選択中の道路点を削除: () => パネル操作.選択中の道路点を削除する(),
        on対象の道を削除: () => パネル操作.対象の道を削除する(),
        on新しい道を始める: () => パネル操作.新しい道を始める(),
        on全ての道を消す: () => パネル操作.全ての道を消す(),
    })
}
