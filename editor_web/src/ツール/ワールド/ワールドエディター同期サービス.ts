import type { ワールド編集状態 } from './編集モデル/index.ts'
import { 散布 } from './編集モデル/index.ts'
import type { ワールド画面部品 } from './画面/index.ts'
import type { ワールドエディター状態 } from './ワールドエディター状態.ts'

// 編集モデルの状態変化を三次元描画部品およびUIパネルへ一括同期する。
export class ワールドエディター同期サービス {
    public constructor(
        private readonly _モデル: ワールド編集状態,
        private readonly _UI状態: ワールドエディター状態,
        private readonly _部品: ワールド画面部品,
    ) {}

    public 全体を同期する(): void {
        this.地形を同期する()
        this.道路を同期する()
        this.建物を同期する()
        this.散布を同期する()
        this.UIを同期する()
    }

    public 地形を同期する(): void {
        const チャンク = this._モデル.チャンクを取得する(this._UI状態.対象チャンク座標)
        this._部品.三次元ビュー.地形.高さ場を更新する(チャンク.高さ場)
        this._部品.三次元ビュー.地形.地表材質を更新する()
    }

    public 道路を同期する(): void {
        const チャンク = this._モデル.チャンクを取得する(this._UI状態.対象チャンク座標)
        this._部品.三次元ビュー.道路帯.更新する(チャンク.道路, チャンク.高さ場)
        this._部品.三次元ビュー.道路ノード.更新する(チャンク.道路, this._UI状態.選択中ノード添字)
    }

    public 建物を同期する(): void {
        const チャンク = this._モデル.チャンクを取得する(this._UI状態.対象チャンク座標)
        this._部品.三次元ビュー.建物.更新する(チャンク.建物)
        this._部品.インスペクター.部品.建物.件数を更新する(チャンク.建物.一覧を取得する().length)
    }

    public 散布を同期する(): void {
        const チャンク = this._モデル.チャンクを取得する(this._UI状態.対象チャンク座標)
        const 散布点一覧 = 散布.標本化を計算する(
            チャンク.散布,
            チャンク.高さ場.一辺のメートル,
            チャンク.道路,
            チャンク.建物.一覧を取得する(),
        )
        this._部品.三次元ビュー.散布.散布点を更新する(散布点一覧, チャンク.高さ場)
        this._部品.インスペクター.部品.散布.本数を更新する(散布点一覧.length)
    }

    public UIを同期する(): void {
        this._部品.インスペクター.表示モードを切り替える(this._UI状態.モード)
        this._部品.インスペクター.部品.道路.選択ノード有効状態を設定する(this._UI状態.選択中ノード添字 >= 0)
        this._部品.インスペクター.部品.建物.選択建物有効状態を設定する(this._UI状態.選択中建物識別子 !== null)
    }
}
