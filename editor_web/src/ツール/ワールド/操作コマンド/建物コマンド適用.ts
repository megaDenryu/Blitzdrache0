import type { 建物を配置する, 建物を移動する, 建物を削除する } from '../../../生成/編集資源契約.ts'
import type { ワールド編集状態 } from '../編集モデル/index.ts'
import type { 建物を配置する差し戻し, 建物を移動する差し戻し, 建物を削除する差し戻し } from './差し戻し断片.ts'

export function 建物を配置する適用(状態: ワールド編集状態, 値: 建物を配置する): 建物を配置する差し戻し {
    const チャンク = 状態.チャンクを取得する(値.チャンク座標)
    チャンク.建物.配置する(値.建物)
    return {
        種類: '建物を配置する',
        チャンク座標: { ...値.チャンク座標 },
        建物識別子: 値.建物.識別子,
    }
}

export function 建物を移動する適用(状態: ワールド編集状態, 値: 建物を移動する): 建物を移動する差し戻し {
    const チャンク = 状態.チャンクを取得する(値.チャンク座標)
    const 元の建物 = チャンク.建物.取得する(値.識別子)
    const 変更前位置 = { ...元の建物.位置 }
    const 変更前向きラジアン = 元の建物.向きラジアン
    チャンク.建物.移動する(値.識別子, 値.新しい位置, 値.新しい向きラジアン)
    return {
        種類: '建物を移動する',
        チャンク座標: { ...値.チャンク座標 },
        識別子: 値.識別子,
        変更前位置,
        変更前向きラジアン,
    }
}

export function 建物を削除する適用(状態: ワールド編集状態, 値: 建物を削除する): 建物を削除する差し戻し {
    const チャンク = 状態.チャンクを取得する(値.チャンク座標)
    const 削除された建物 = チャンク.建物.削除する(値.識別子)
    return {
        種類: '建物を削除する',
        チャンク座標: { ...値.チャンク座標 },
        削除された建物,
    }
}
