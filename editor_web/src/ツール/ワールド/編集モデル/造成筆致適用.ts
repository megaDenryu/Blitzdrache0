import type { 位置3次元, 造成筆致 } from '../../../生成/編集資源契約.ts'

// 単一通過点の造成筆致を格子データへ直接適用する。
export function 単一通過点の造成筆致を適用する(
    格子データ: Float32Array,
    解像度: number,
    一辺のメートル: number,
    格子間隔: number,
    通過点: 位置3次元,
    筆致: 造成筆致,
): void {
    let 平均高さ = 0
    let 平均対象点数 = 0
    if (筆致.種別 === '平す') {
        for (let gz = 0; gz < 解像度; gz++) {
            for (let gx = 0; gx < 解像度; gx++) {
                const wx = gx * 格子間隔 - 一辺のメートル / 2
                const wz = gz * 格子間隔 - 一辺のメートル / 2
                if (Math.hypot(wx - 通過点.x, wz - 通過点.z) < 筆致.半径メートル) {
                    const インデックス = gz * 解像度 + gx
                    平均高さ += 格子データ[インデックス] ?? 0
                    平均対象点数++
                }
            }
        }
        if (平均対象点数 > 0) 平均高さ /= 平均対象点数
    }

    for (let gz = 0; gz < 解像度; gz++) {
        for (let gx = 0; gx < 解像度; gx++) {
            const wx = gx * 格子間隔 - 一辺のメートル / 2
            const wz = gz * 格子間隔 - 一辺のメートル / 2
            const 距離 = Math.hypot(wx - 通過点.x, wz - 通過点.z)
            if (距離 < 筆致.半径メートル) {
                const コサイン減衰 = Math.cos((距離 / 筆致.半径メートル) * (Math.PI / 2))
                const インデックス = gz * 解像度 + gx
                const 現在高さ = 格子データ[インデックス] ?? 0
                if (筆致.種別 === '盛る') {
                    格子データ[インデックス] = 現在高さ + 筆致.強さ * コサイン減衰
                } else if (筆致.種別 === '平す') {
                    格子データ[インデックス] = 現在高さ + (平均高さ - 現在高さ) * 0.2 * コサイン減衰
                } else if (筆致.種別 === '水平にする') {
                    格子データ[インデックス] = 現在高さ + (通過点.y - 現在高さ) * 0.3 * コサイン減衰
                }
            }
        }
    }
}
