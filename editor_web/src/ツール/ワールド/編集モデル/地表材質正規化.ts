// 4層の地表材質（草・泥・岩・砂）の重みを正規化し、合計を厳密に255にする。
// 切り捨てによる端数不足は、最大剰余法により余りの大きい層へ順に分配する。
export function 合計255へ正規化する(
    草: number,
    泥: number,
    岩: number,
    砂: number,
): [number, number, number, number] {
    const 合計 = 草 + 泥 + 岩 + 砂
    if (合計 <= 0) return [255, 0, 0, 0]
    const 比率 = [草 / 合計 * 255, 泥 / 合計 * 255, 岩 / 合計 * 255, 砂 / 合計 * 255]
    const 整数部 = [
        Math.floor(比率[0] ?? 0),
        Math.floor(比率[1] ?? 0),
        Math.floor(比率[2] ?? 0),
        Math.floor(比率[3] ?? 0),
    ]
    const 端数不足 = 255 - (整数部[0]! + 整数部[1]! + 整数部[2]! + 整数部[3]!)
    const 剰余一覧 = 比率.map((v, i) => ({ インデックス: i, 剰余: v - (整数部[i] ?? 0) }))
    剰余一覧.sort((a, b) => b.剰余 - a.剰余)
    for (let i = 0; i < 端数不足; i++) {
        const 対象 = 剰余一覧[i % 4]!
        整数部[対象.インデックス] = (整数部[対象.インデックス] ?? 0) + 1
    }
    return [整数部[0]!, 整数部[1]!, 整数部[2]!, 整数部[3]!]
}
