import type { 大域世界構造, チャンク構造 } from '../../../生成/編集資源契約.ts'
import { ワールド編集状態 } from './ワールド編集状態.ts'

// モックアップ仕様に準拠した初期チャンクと編集モデルを構築する。
export function 初期ワールド状態を生成する(): ワールド編集状態 {
    const 大域構造: 大域世界構造 = {
        区画割り: {
            一辺のメートル: 256,
            軸あたりチャンク数: 1,
            チャンクあたり格子解像度: 128,
        },
        広域道路: {
            制御点列: [],
            全幅メートル: 8.0,
            細分割数: 80,
        },
    }

    const 状態 = new ワールド編集状態(大域構造)
    // チャンク格子の頂点数はサーバーの契約と同じく「チャンクあたり格子解像度+1」(1px重複共有)
    const 頂点数 = 大域構造.区画割り.チャンクあたり格子解像度 + 1
    const チャンク一辺 = 大域構造.区画割り.一辺のメートル
    const 格子間隔 = チャンク一辺 / (頂点数 - 1)
    const 半分 = チャンク一辺 / 2

    const 高さデータ = new Float32Array(頂点数 * 頂点数)
    const 材質データ = new Uint8Array(頂点数 * 頂点数 * 4)

    for (let gz = 0; gz < 頂点数; gz++) {
        for (let gx = 0; gx < 頂点数; gx++) {
            const wx = gx * 格子間隔 - 半分
            const wz = gz * 格子間隔 - 半分

            let h = Math.sin(wx * 0.02) * Math.cos(wz * 0.02) * 8.0
            h += Math.sin(wx * 0.05 + 1.2) * Math.sin(wz * 0.05) * 3.0
            h += Math.sin(wx * 0.1) * Math.cos(wz * 0.1) * 0.8

            const 添字 = gz * 頂点数 + gx
            高さデータ[添字] = h

            材質データ[添字 * 4 + 0] = 255
            材質データ[添字 * 4 + 1] = 0
            材質データ[添字 * 4 + 2] = 0
            材質データ[添字 * 4 + 3] = 0
        }
    }

    const チャンク構造設定: チャンク構造 = {
        道路: {
            制御点列: [
                { x: -80, y: 0, z: -60 },
                { x: -30, y: 0, z: -20 },
                { x: 20, y: 0, z: 20 },
                { x: 75, y: 0, z: 70 },
            ],
            全幅メートル: 8.0,
            散布除外バッファメートル: 14.0,
            細分割数: 80,
        },
        建物一覧: [],
        散布: {
            最小間隔メートル: 5.5,
            乱数の種: 12345n,
        },
    }

    const チャンク = 状態.チャンクを登録する({ x: 0, z: 0 }, チャンク構造設定, 高さデータ, 材質データ)
    for (let i = 0; i < チャンク.道路.制御点列.length; i++) {
        const 点 = チャンク.道路.制御点列[i]
        if (点 !== undefined) {
            点.y = チャンク.高さ場.標本高さを取得する(点.x, 点.z)
        }
    }

    return 状態
}
