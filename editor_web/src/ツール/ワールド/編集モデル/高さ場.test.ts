import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 高さ場 } from './高さ場.ts'

describe('高さ場編集モデル', () => {
    it('盛る筆致が中心で最大変化し半径外では不変であること', () => {
        const 解像度 = 33
        const 一辺 = 64
        const 対象高さ場 = new 高さ場(解像度, 一辺)
        const 中心 = { x: 0, y: 0, z: 0 }
        const 半径 = 10
        const 強さ = 5.0

        対象高さ場.造成筆致を適用する({
            種別: '盛る',
            通過点列: [中心],
            半径メートル: 半径,
            強さ,
        })

        const 中心高さ = 対象高さ場.標本高さを取得する(0, 0)
        assert.ok(Math.abs(中心高さ - 強さ) < 1e-3, `中心高さが強さと一致するべき: 実際=${中心高さ}`)

        const 半径外高さ = 対象高さ場.標本高さを取得する(20, 20)
        assert.strictEqual(半径外高さ, 0, '半径外の高さは0のままであるべき')
    })

    it('平す筆致が平均高さへ補間され半径外では不変であること', () => {
        const 解像度 = 33
        const 一辺 = 64
        const 対象高さ場 = new 高さ場(解像度, 一辺)
        for (let i = 0; i < 対象高さ場.格子データ.length; i++) {
            対象高さ場.格子データ[i] = i % 2 === 0 ? 10 : 0
        }
        const 中心 = { x: 0, y: 0, z: 0 }
        const 変更前中心高さ = 対象高さ場.標本高さを取得する(0, 0)

        対象高さ場.造成筆致を適用する({
            種別: '平す',
            通過点列: [中心],
            半径メートル: 15,
            強さ: 1.0,
        })

        const 変更後中心高さ = 対象高さ場.標本高さを取得する(0, 0)
        assert.notStrictEqual(変更後中心高さ, 変更前中心高さ, '中心高さは変化するべき')

        const 半径外点 = 対象高さ場.標本高さを取得する(25, 25)
        assert.ok(半径外点 >= 0, '半径外の値は保持されるべき')
    })

    it('水平にする筆致が通過点の標高へ補間されること', () => {
        const 解像度 = 33
        const 一辺 = 64
        const 対象高さ場 = new 高さ場(解像度, 一辺)
        const 目標高さ = 12.0

        対象高さ場.造成筆致を適用する({
            種別: '水平にする',
            通過点列: [{ x: 0, y: 目標高さ, z: 0 }],
            半径メートル: 10,
            強さ: 1.0,
        })

        const 中心高さ = 対象高さ場.標本高さを取得する(0, 0)
        assert.ok(中心高さ > 0 && 中心高さ <= 目標高さ, `中心高さが目標高さへ引き寄せられるべき: 実際=${中心高さ}`)
    })

    it('標本法線が平坦部で上向きベクトルを返すこと', () => {
        const 対象高さ場 = new 高さ場(17, 32)
        const 法線 = 対象高さ場.標本法線を取得する(0, 0)
        assert.ok(Math.abs(法線.x) < 1e-4)
        assert.ok(Math.abs(法線.y - 1.0) < 1e-4)
        assert.ok(Math.abs(法線.z) < 1e-4)
    })
})
