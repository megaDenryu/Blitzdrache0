import type { 大域世界構造, チャンク座標, チャンク構造, 位置3次元 } from '../../../生成/編集資源契約.ts'
import { 道路スプライン } from './道路スプライン.ts'
import { 高さ場 } from './高さ場.ts'
import { チャンク編集状態 } from './チャンク状態.ts'

// 大域世界および各チャンクの編集状態を一元管理する。
export class ワールド編集状態 {
    public readonly 大域世界構造: 大域世界構造
    public readonly 広域道路: 道路スプライン
    public readonly 大域高さ場: 高さ場
    public readonly チャンク一覧マップ: Map<string, チャンク編集状態>
    public 選択中チャンク座標: チャンク座標 | null

    public constructor(
        構造: 大域世界構造,
        初期大域高さデータ?: Float32Array,
    ) {
        this.大域世界構造 = {
            区画割り: { ...構造.区画割り },
            広域道路: {
                制御点列: 構造.広域道路.制御点列.map((p: 位置3次元) => ({ ...p })),
                全幅メートル: 構造.広域道路.全幅メートル,
                細分割数: 構造.広域道路.細分割数,
            },
        }
        this.広域道路 = new 道路スプライン(構造.広域道路)
        const 大域格子解像度 = 構造.区画割り.軸あたりチャンク数 * 構造.区画割り.チャンクあたり格子解像度 + 1
        this.大域高さ場 = new 高さ場(大域格子解像度, 構造.区画割り.一辺のメートル, 初期大域高さデータ)
        this.チャンク一覧マップ = new Map<string, チャンク編集状態>()
        this.選択中チャンク座標 = null
    }

    public static チャンクキーを生成する(座標: チャンク座標): string {
        return `${座標.x},${座標.z}`
    }

    public チャンクを登録する(
        座標: チャンク座標,
        構造: チャンク構造,
        初期高さデータ?: Float32Array,
        初期材質データ?: Uint8Array,
    ): チャンク編集状態 {
        const キー = ワールド編集状態.チャンクキーを生成する(座標)
        const チャンク一辺 = this.大域世界構造.区画割り.一辺のメートル / this.大域世界構造.区画割り.軸あたりチャンク数
        // サーバーの契約(world_layout.rsのチャンク格子の頂点数)は「チャンクあたり格子解像度+1」の
        // 頂点数を求める。隣のチャンクと境界の頂点を共有する1px重複共有の設計であり、
        // 大域のマザーハイトマップ(チャンク数×解像度+1)と同じ規則をチャンク単独へ適用したものである
        const 頂点数 = this.大域世界構造.区画割り.チャンクあたり格子解像度 + 1
        const 状態 = new チャンク編集状態(座標, 構造, チャンク一辺, 頂点数, 初期高さデータ, 初期材質データ)
        this.チャンク一覧マップ.set(キー, 状態)
        return 状態
    }

    public チャンクを取得する(座標: チャンク座標): チャンク編集状態 {
        const キー = ワールド編集状態.チャンクキーを生成する(座標)
        const 状態 = this.チャンク一覧マップ.get(キー)
        if (状態 === undefined) {
            throw new Error(`チャンクが存在しない: (${座標.x}, ${座標.z})`)
        }
        return 状態
    }

    public チャンクが存在するか(座標: チャンク座標): boolean {
        const キー = ワールド編集状態.チャンクキーを生成する(座標)
        return this.チャンク一覧マップ.has(キー)
    }

    public 状態を上書きする(新状態: ワールド編集状態): void {
        this.大域世界構造.区画割り = { ...新状態.大域世界構造.区画割り }
        this.大域世界構造.広域道路 = { ...新状態.大域世界構造.広域道路 }
        this.広域道路.制御点列.length = 0
        for (const p of 新状態.広域道路.制御点列) {
            this.広域道路.制御点列.push({ ...p })
        }
        this.大域高さ場.格子データ.set(新状態.大域高さ場.格子データ)
        this.チャンク一覧マップ.clear()
        for (const [k, c] of 新状態.チャンク一覧マップ) {
            this.チャンク一覧マップ.set(k, c)
        }
        this.選択中チャンク座標 = 新状態.選択中チャンク座標
    }
}
