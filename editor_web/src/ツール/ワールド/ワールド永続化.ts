import type { プロジェクト保管庫接続 } from '../../境界/通信/index.ts'
import type { チャンク座標, チャンク構造, 世界の区画割り } from '../../生成/編集資源契約.ts'
import { ワールド編集状態, 初期ワールド状態を生成する } from './編集モデル/index.ts'

// ワールドパイプラインエディターの編集状態と保管庫の間で相互変換と保存・読込を行う。
export async function ワールド状態を保管庫から読み込む(
    保管庫: プロジェクト保管庫接続,
    対象座標: チャンク座標 = { x: 0, z: 0 },
): Promise<{ 状態: ワールド編集状態; 結果種別: '読込成功' | '初期生成' }> {
    const 大域構造結果 = await 保管庫.大域世界の構造を読む()
    if (大域構造結果.種別 === '失敗') {
        throw new Error(`大域世界構造の読込に失敗した: ${大域構造結果.エラー.種別} ${大域構造結果.エラー.説明}`)
    }
    if (大域構造結果.種別 === '無し') {
        return { 状態: 初期ワールド状態を生成する(対象座標), 結果種別: '初期生成' }
    }

    const 大域高さ結果 = await 保管庫.大域世界の高さ格子を読む()
    const 大域高さ = 大域高さ結果.種別 === '成功' ? new Float32Array(大域高さ結果.値) : undefined
    const 状態 = new ワールド編集状態(大域構造結果.値, 大域高さ)

    const チャンク結果 = await 保管庫.チャンクの構造を読む(対象座標)
    if (チャンク結果.種別 === '失敗') {
        throw new Error(`チャンク構造の読込に失敗した: ${チャンク結果.エラー.種別} ${チャンク結果.エラー.説明}`)
    }

    if (チャンク結果.種別 === '成功') {
        const 高さ結果 = await 保管庫.チャンクの高さ格子を読む(対象座標)
        const 材質結果 = await 保管庫.チャンクの材質重みを読む(対象座標)
        const 高さ = 高さ結果.種別 === '成功' ? new Float32Array(高さ結果.値) : undefined
        const 材質 = 材質結果.種別 === '成功' ? new Uint8Array(材質結果.値) : undefined
        状態.チャンクを登録する(対象座標, チャンク結果.値, 高さ, 材質)
    } else {
        const 初期 = 初期ワールド状態を生成する(対象座標, 大域構造結果.値)
        const 初期チャンク = 初期.チャンクを取得する(対象座標)
        状態.チャンクを登録する(対象座標, 初期チャンク.構造を取得する(), 初期チャンク.高さ場.格子データ, 初期チャンク.地表材質.材質データ)
    }
    状態.選択中チャンク座標 = 対象座標
    return { 状態, 結果種別: '読込成功' }
}

export async function ワールド状態を保管庫へ保存する(
    保管庫: プロジェクト保管庫接続,
    状態: ワールド編集状態,
): Promise<void> {
    const 大域構造結果 = await 保管庫.大域世界の構造を読む()
    if (大域構造結果.種別 === '失敗') {
        throw new Error(`大域世界構造の読込に失敗した: ${大域構造結果.エラー.種別} ${大域構造結果.エラー.説明}`)
    }

    if (大域構造結果.種別 === '無し') {
        // 保管庫に大域構造がまだ無いときだけ、区画割り整合のために大域構造を保存する
        const 大域構造保存 = await 保管庫.大域世界の構造を保存する(状態.大域世界構造)
        if (大域構造保存.種別 === '失敗') {
            throw new Error(`大域世界構造の保存に失敗した: ${大域構造保存.エラー.種別} ${大域構造保存.エラー.説明}`)
        }
    } else {
        // あるときは読んで区画割りの整合確認のみを行い、上書きしない
        区画割りの整合を確認する(大域構造結果.値.区画割り, 状態.大域世界構造.区画割り)
    }

    // 注意: 大域世界の高さ格子・広域道路は大域世界の正本であり、チャンクタブの保存では一切書かない
    for (const [, チャンク] of 状態.チャンク一覧マップ) {
        await チャンクを保存する(保管庫, チャンク.座標, チャンク.構造を取得する(), チャンク.高さ場.格子データ, チャンク.地表材質.材質データ)
    }
}

function 区画割りの整合を確認する(保存済み: 世界の区画割り, 状態側: 世界の区画割り): void {
    if (
        保存済み.一辺のメートル !== 状態側.一辺のメートル ||
        保存済み.軸あたりチャンク数 !== 状態側.軸あたりチャンク数 ||
        保存済み.チャンクあたり格子解像度 !== 状態側.チャンクあたり格子解像度
    ) {
        throw new Error(`大域世界構造の区画割りとチャンク状態の区画割りが一致しない: 保管庫(${保存済み.一辺のメートル}m, ${保存済み.軸あたりチャンク数}軸, 解像度${保存済み.チャンクあたり格子解像度}) vs 状態(${状態側.一辺のメートル}m, ${状態側.軸あたりチャンク数}軸, 解像度${状態側.チャンクあたり格子解像度})`)
    }
}

async function チャンクを保存する(
    保管庫: プロジェクト保管庫接続,
    座標: チャンク座標,
    構造: チャンク構造,
    高さ: Float32Array,
    材質: Uint8Array,
): Promise<void> {
    const 構造結果 = await 保管庫.チャンクの構造を保存する(座標, 構造)
    if (構造結果.種別 === '失敗') throw new Error(`チャンク(${座標.x},${座標.z})構造の保存に失敗した: ${構造結果.エラー.種別} ${構造結果.エラー.説明}`)
    const 高さ結果 = await 保管庫.チャンクの高さ格子を保存する(座標, 高さ.buffer)
    if (高さ結果.種別 === '失敗') throw new Error(`チャンク(${座標.x},${座標.z})高さ格子の保存に失敗した: ${高さ結果.エラー.種別} ${高さ結果.エラー.説明}`)
    const 材質結果 = await 保管庫.チャンクの材質重みを保存する(座標, 材質.buffer)
    if (材質結果.種別 === '失敗') throw new Error(`チャンク(${座標.x},${座標.z})材質重みの保存に失敗した: ${材質結果.エラー.種別} ${材質結果.エラー.説明}`)
}
