import type { プロジェクト保管庫接続 } from '../../境界/通信/index.ts'
import type { マテリアル台帳パネル } from './画面/index.ts'
import type { マテリアル台帳の管理 } from './編集モデル/index.ts'
import { パネル操作を実行する, type パネル操作結果 } from '../チャンク編集/永続化パネル操作.ts'

// マテリアル台帳パネルの一覧編集・層割当・保存永続化イベントを、編集モデルと保管庫接続へ配線する。
// 戻り値は現在の管理の状態でパネルの一覧を再構築する関数であり、起動時読込がその同じ配線を
// 使って初期表示するために返す(読込専用の別配線を重ねて張らないため)。
export function マテリアル台帳イベントを配線する(
    パネル: マテリアル台帳パネル, 管理: マテリアル台帳の管理, 保管庫: プロジェクト保管庫接続
): () => void {
    const 表示を再構築する = (): void => { パネル.表示を更新する(管理.台帳を取得する(), 一覧配線) }
    const 一覧配線 = {
        on名前変更: (添字: number, 新しい材質名: string): void => {
            管理.材質名を変更する(添字, 新しい材質名)
            パネル.層割当の選択肢だけを更新する(管理.台帳を取得する())
        },
        on識別色変更: (添字: number, 新しい識別色: string): void => {
            管理.識別色を変更する(添字, 新しい識別色)
        },
        on削除: (添字: number): void => {
            管理.材質を削除する(添字)
            表示を再構築する()
        },
    }

    パネル.配線する(
        { on割当変更: (層, 材質名) => 管理.層の割当を変更する(層, 材質名) },
        () => { 管理.材質を追加する(); 表示を再構築する() },
    )

    const 保存する = async (): Promise<パネル操作結果> => {
        const 結果 = await 保管庫.マテリアル台帳を保存する(管理.台帳を取得する())
        if (結果.種別 === '失敗') {
            return { 文言: `保存失敗: ${結果.エラー.種別} ${結果.エラー.説明}`, エラーか: true }
        }
        return { 文言: '保存完了', エラーか: false }
    }
    const 読み込む = async (): Promise<パネル操作結果> => {
        const 結果 = await 保管庫.マテリアル台帳を読む()
        if (結果.種別 === '失敗') {
            return { 文言: `読込失敗: ${結果.エラー.種別} ${結果.エラー.説明}`, エラーか: true }
        }
        if (結果.種別 === '成功') 管理.状態を上書きする(結果.値)
        表示を再構築する()
        return { 文言: 結果.種別 === '成功' ? '読み込み完了' : '未保存: 既定の台帳を表示中', エラーか: false }
    }

    パネル.永続化.on保存クリック(() => { void パネル操作を実行する(パネル.永続化, '保存中...', 保存する, '保存失敗') })
    パネル.永続化.on読込クリック(() => { void パネル操作を実行する(パネル.永続化, '読み込み中...', 読み込む, '読込失敗') })

    表示を再構築する()
    return 表示を再構築する
}

export async function 起動時にマテリアル台帳を読み込む(
    パネル: マテリアル台帳パネル,
    管理: マテリアル台帳の管理,
    保管庫: プロジェクト保管庫接続,
    表示を再構築する: () => void,
): Promise<void> {
    try {
        const 結果 = await 保管庫.マテリアル台帳を読む()
        if (結果.種別 === '成功') {
            管理.状態を上書きする(結果.値)
            パネル.永続化.状態文言を更新する('読込完了(起動時)', false)
        } else if (結果.種別 === '無し') {
            パネル.永続化.状態文言を更新する('未保存: 既定の台帳を表示中', false)
        } else {
            パネル.永続化.状態文言を更新する(`起動時読込失敗: ${結果.エラー.種別} ${結果.エラー.説明}`, true)
        }
    } catch (原因: unknown) {
        const メッセージ = 原因 instanceof Error ? 原因.message : String(原因)
        パネル.永続化.状態文言を更新する(`起動時読込失敗: ${メッセージ}`, true)
    }
    表示を再構築する()
}
