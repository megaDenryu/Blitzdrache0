import type { 建物の格子接続 } from '../../境界/通信/index.ts'
import type { 建物編集画面 } from './画面/index.ts'
import type { 建物編集の状態 } from './建物編集の状態.ts'

// 画面と編集の状態と格子の接続を保持し、保存と読み直しをメソッドで公開する操作サービス。
// 触りの同期(建物編集同期サービス)から分けるのは、呼ばれる時機が違うためである。触りは升目を
// 触るたびに動き、こちらはボタンを押したときだけ動いてサーバーと往復する。
export class 建物の格子の永続化係 {
    public constructor(
        private readonly _画面: 建物編集画面,
        private readonly _状態: 建物編集の状態,
        private readonly _接続: 建物の格子接続,
    ) {}

    // 保存が通ると、サーバー側で建物外形カタログが組み直される。通らなかった理由はそのまま画面へ出す
    // (無言で保存できたことにしない)。
    public async 保存する(): Promise<void> {
        this._画面.永続化.状態文言を更新する('保存中')
        const 結果 = await this._接続.建物の格子を保存する(this._状態.履歴.モデル.契約の値へ写す())
        if (結果.種別 === '成功') {
            this._画面.永続化.状態文言を更新する('保存済み')
            return
        }
        this._画面.永続化.状態文言を更新する(`保存できない: ${結果.エラー.種別} ${結果.エラー.説明}`, true)
    }

    // 保存済みの正本を読んで編集の状態を作り直す。まだ保存されていない建物は、いまの内容を残したまま理由を出す。
    public async 読み直す(表示を作り直す: () => void): Promise<void> {
        const 結果 = await this._接続.建物の格子を読む(this._状態.履歴.モデル.名乗り.建物定義ID)
        if (結果.種別 === '失敗') {
            this._画面.永続化.状態文言を更新する(`読み込めない: ${結果.エラー.種別} ${結果.エラー.説明}`, true)
            return
        }
        if (結果.種別 === '無し') {
            this._画面.永続化.状態文言を更新する('まだ保存されていない')
            return
        }
        this._状態.読み直した格子で作り直す(結果.値)
        this._画面.表示名入力.setValue(結果.値.表示名)
        this._画面.永続化.状態文言を更新する('読み込み済み')
        表示を作り直す()
    }
}
