import type { 升目の座標 } from '../../生成/編集資源契約.ts'
import type { 表示名の編集をまとめる係 } from '../../文書の表示名の編集/index.ts'
import { 入口方向が向く側面を読む, type 升目の側面, type 煙突の段数 } from './編集モデル/index.ts'
import type { 建物編集画面 } from './画面/index.ts'
import type { 升目への筆, 面への筆 } from './操作コマンド/index.ts'
import type { 建物編集の状態 } from './建物編集の状態.ts'

// 人が画面へ行える触りの一覧。表示係が各パネルへ配る配線の元であり、実体は同期サービスのメソッドである。
// 表示係が触りを自分で持たないのは、表示係が状態を読むだけで1つも書き換えないためである。
export interface I建物編集の触り {
    階を選ぶ(階: number): void
    升目への筆を選ぶ(筆: 升目への筆): void
    面への筆を選ぶ(筆: 面への筆): void
    煙突の段数を選ぶ(段数: 煙突の段数): void
    入口の向く面を選ぶ(側面: 升目の側面): void
    升目を触る(座標: 升目の座標): void
    升目を消す(座標: 升目の座標): void
    面を触る(座標: 升目の座標, 側面: 升目の側面): void
    面を消す(座標: 升目の座標, 側面: 升目の側面): void
    表示名が入力された(入力中の表示名: string): void
    表示名が決まった(新しい表示名: string): void
    取り消す(): void
    やり直す(): void
    識別色の重ねを切り替える(): void
    建物ぜんたいを写す(): void
}

// 建物の表示名が変わったことを受け取る、ツールの外側の相手の規約。文書タブの見出しを追随させるために使う。
// 楽曲編集ツールも同じ形の口を持ち、入り口の1つの実装が両方の届け先になる。
export interface I建物の表示名の届け先 {
    表示名が変わった(新しい表示名: string): void
}

// 画面と編集の状態を保持し、いまの状態から画面のパネルを作り直す操作サービス。
// 同期サービスから分けるのは、触れる材料が違うためである。ここは状態を読むだけで1つも書き換えず、
// 書き換えは受け取った触りの先が行う。
//
// 変わった箇所だけを差し替えず全体を作り直すのは、1回の触りで隣と真下の升目の継ぎ目まで変わるためである
// (格子1件の升目は数十の規模であり、作り直しの費用は人の操作1回に対して問題にならない)。
export class 建物編集の表示係 {
    public constructor(
        private readonly _画面: 建物編集画面,
        private readonly _状態: 建物編集の状態,
        private readonly _表示名の編集: 表示名の編集をまとめる係,
    ) {}

    public 作り直す(触り: I建物編集の触り): void {
        const モデル = this._状態.履歴.モデル
        this._画面.部品.インスペクター.階の一覧.再構築する(
            this._状態.最上階(),
            this._状態.選んだ階,
            (階) => this._状態.その階の升目の数(階),
            { on階を選ぶ: (階) => 触り.階を選ぶ(階) },
        )
        this._画面.部品.部品の棚.筆.再構築する(
            this._状態.選んだ升目への筆,
            this._状態.選んだ面への筆,
            this._状態.選んだ煙突の段数,
            {
                on升目への筆を選ぶ: (筆) => 触り.升目への筆を選ぶ(筆),
                on面への筆を選ぶ: (筆) => 触り.面への筆を選ぶ(筆),
                on煙突の段数を選ぶ: (段数) => 触り.煙突の段数を選ぶ(段数),
            },
        )
        this._画面.部品.インスペクター.入口の向き.再構築する(入口方向が向く側面を読む(モデル.名乗り.入口のローカル方向), {
            on入口の向く面を選ぶ: (側面) => 触り.入口の向く面を選ぶ(側面),
        })
        this._画面.部品.平面図.再構築する(モデル, this._状態.選んだ階, this._状態.選んでいる升目, {
            on升目を触る: (座標) => 触り.升目を触る(座標),
            on升目を消す: (座標) => 触り.升目を消す(座標),
            on面を触る: (座標, 側面) => 触り.面を触る(座標, 側面),
            on面を消す: (座標, 側面) => 触り.面を消す(座標, 側面),
        })
        this._画面.部品.三次元.再構築する(モデル, this._状態.選んでいる升目, this._状態.識別色を重ねるか)
        this._画面.部品.インスペクター.選んでいる升目.表示を更新する(this._状態.選んでいる升目)
        this._画面.部品.建物名.表示を更新する(モデル.名乗り.表示名)
        this.取り消しとやり直しの活性を更新する()
        this._表示名の編集.正本の表示名に合わせる(モデル.名乗り.表示名)
    }

    public 取り消しとやり直しの活性を更新する(): void {
        this._画面.部品.操作帯.表示を更新する(
            this._状態.履歴.取り消せるか,
            this._状態.履歴.やり直せるか,
            this._状態.識別色を重ねるか,
        )
    }
}
