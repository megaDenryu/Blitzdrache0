import type { 建物の格子 } from '../../../生成/編集資源契約.ts'
import { 建物の格子の編集モデル } from '../編集モデル/index.ts'

// 建物の編集操作1回を表すコマンド。実行の前後で格子の全体を写して持つのは、
// 升目を1つ置くだけでも隣と真下の升目の継ぎ目が同時に変わるためであり、
// 変わった箇所を1件ずつ数え上げる形にすると取り消しの復元が編集モデルの整えと二重管理になる。
//
// 格子1件の升目は数十の規模であり、写しの費用は人の操作1回に対して問題にならない。
export class 建物編集コマンド {
    private constructor(
        public readonly 名前: string,
        private readonly _実行前の格子: 建物の格子,
        private readonly _実行後の格子: 建物の格子,
    ) {}

    // 名指した操作をモデルへ適用し、適用の前後を写したコマンドを返す。適用が何も変えなかったときは「無し」を返す。
    public static モデルへ適用して記録する(
        名前: string,
        モデル: 建物の格子の編集モデル,
        操作する: (モデル: 建物の格子の編集モデル) => void,
    ): 建物編集コマンド | undefined {
        const 実行前の格子 = モデル.契約の値へ写す()
        操作する(モデル)
        const 実行後の格子 = モデル.契約の値へ写す()
        if (JSON.stringify(実行前の格子) === JSON.stringify(実行後の格子)) return undefined
        return new 建物編集コマンド(名前, 実行前の格子, 実行後の格子)
    }

    public 取り消した後のモデル(): 建物の格子の編集モデル {
        return 建物の格子の編集モデル.契約の値から復元する(this._実行前の格子)
    }

    public やり直した後のモデル(): 建物の格子の編集モデル {
        return 建物の格子の編集モデル.契約の値から復元する(this._実行後の格子)
    }
}
