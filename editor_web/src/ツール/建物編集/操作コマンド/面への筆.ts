import type { 升目の座標 } from '../../../生成/編集資源契約.ts'
import {
    壁を入れない,
    壁を入れる,
    煙突の段数,
    type 升目の側面,
    type 建物の格子の編集モデル,
    type 面へ壁を入れられない理由,
    type 面へ飾りを付けられない理由,
} from '../編集モデル/index.ts'

// 平面図で升目の周りの帯を触ったときに何が起きるかの選択と、その適用。升目そのものへ効く筆は`升目への筆`が持つ。
// 壁の筆と飾りの筆を1つの並びにするのは、どちらも同じ帯を触って効くためであり、断る事情だけが違う。

export type 壁への筆 = '平壁' | '窓壁' | '扉枠付きの壁' | '壁を外す'

export type 飾りへの筆 = '出窓を差し込む' | '煙突を立てる' | '飾りを外す'

export type 面への筆 = 壁への筆 | 飾りへの筆

export const 全ての面への筆: readonly 面への筆[] = ['平壁', '窓壁', '扉枠付きの壁', '壁を外す', '出窓を差し込む', '煙突を立てる', '飾りを外す']

const 飾りへの筆の並び: readonly 面への筆[] = ['出窓を差し込む', '煙突を立てる', '飾りを外す']

function 飾りへの筆か(筆: 面への筆): 筆 is 飾りへの筆 {
    return 飾りへの筆の並び.includes(筆)
}

// 平面図で面を右クリックしたときに効く筆。いま選んでいる筆が飾りの筆なら飾りを、壁の筆なら壁を外す。
// 消す対象を選んでいる筆に合わせるのは、左で置いたものが右で消えるという対応を人が作れるようにするためである。
export function 選んだ筆に対応する消しの筆(筆: 面への筆): 面への筆 {
    return 飾りへの筆か(筆) ? '飾りを外す' : '壁を外す'
}

export function 面への筆が断る理由(
    モデル: 建物の格子の編集モデル,
    筆: 面への筆,
    座標: 升目の座標,
    側面: 升目の側面,
): 面へ壁を入れられない理由 | 面へ飾りを付けられない理由 | undefined {
    if (飾りへの筆か(筆)) return モデル.面へ飾りを付けられない理由を調べる(座標, 側面)
    return 筆 === '壁を外す' ? undefined : モデル.面へ壁を入れられない理由を調べる(座標, 側面)
}

export function 面への筆を適用する(
    モデル: 建物の格子の編集モデル,
    筆: 面への筆,
    座標: 升目の座標,
    側面: 升目の側面,
    選んだ煙突の段数: 煙突の段数,
): void {
    switch (筆) {
        case '平壁':
        case '窓壁':
        case '扉枠付きの壁':
            return モデル.側面の値を定める(座標, 側面, 壁を入れる(筆))
        case '壁を外す':
            return モデル.側面の値を定める(座標, 側面, 壁を入れない())
        case '出窓を差し込む':
            return モデル.面の飾りを定める(座標, 側面, { 種類: '出窓を差し込む' })
        case '煙突を立てる':
            return モデル.面の飾りを定める(座標, 側面, { 種類: '煙突を立てる', 値: { 段数: 選んだ煙突の段数.段数 } })
        case '飾りを外す':
            return モデル.面の飾りを定める(座標, 側面, { 種類: '付けない' })
    }
}
