import type { 升目の座標 } from '../../../生成/編集資源契約.ts'
import { 壁を入れない, 壁を入れる, type 升目の側面, type 建物の格子の編集モデル } from '../編集モデル/index.ts'

// 平面図で升目を触ったときに何が起きるかの選択。升目そのものへ効く筆と、面へ効く筆に分かれる。
export type 升目への筆 = '升目を置く' | '升目を消す' | '床を張る' | '床を外す' | '屋根を載せる' | '屋根を外す' | '根にする'

export type 面への筆 = '平壁' | '窓壁' | '扉枠付きの壁' | '壁を外す'

export const 全ての升目への筆: readonly 升目への筆[] = [
    '升目を置く',
    '升目を消す',
    '床を張る',
    '床を外す',
    '屋根を載せる',
    '屋根を外す',
    '根にする',
]

export const 全ての面への筆: readonly 面への筆[] = ['平壁', '窓壁', '扉枠付きの壁', '壁を外す']

export function 升目への筆を適用する(モデル: 建物の格子の編集モデル, 筆: 升目への筆, 座標: 升目の座標): void {
    switch (筆) {
        case '升目を置く':
            return モデル.升目を置く(座標)
        case '升目を消す':
            return モデル.升目を消す(座標)
        case '床を張る':
            return モデル.床を定める(座標, '張る')
        case '床を外す':
            return モデル.床を定める(座標, '張らない')
        case '屋根を載せる':
            return モデル.屋根を定める(座標, '載せる')
        case '屋根を外す':
            return モデル.屋根を定める(座標, '載せない')
        case '根にする':
            return モデル.根を定める(座標)
    }
}

export function 面への筆を適用する(
    モデル: 建物の格子の編集モデル,
    筆: 面への筆,
    座標: 升目の座標,
    側面: 升目の側面,
): void {
    if (筆 === '壁を外す') {
        モデル.側面の値を定める(座標, 側面, 壁を入れない())
        return
    }
    モデル.側面の値を定める(座標, 側面, 壁を入れる(筆))
}
