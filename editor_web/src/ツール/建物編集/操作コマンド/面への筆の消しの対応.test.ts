import { strictEqual } from 'node:assert/strict'
import { describe, it } from 'node:test'
import { 全ての面への筆, 選んだ筆に対応する消しの筆 } from './面への筆.ts'

// 平面図の面の帯は、左クリックで選んだ筆を置き、右クリックでその筆に対応するものを消す。
// 左で置いたものが右で消えるという対応が全ての筆で成り立つことを確かめる。
// 参照: `~/.claude/skills/エディター制作` 第7条「操作の割り当ては、編集の種類ごとに1つに決める」
describe('面への筆に対応する消しの筆', () => {
    it('壁の筆を選んでいるときは壁を外す', () => {
        for (const 筆 of ['平壁', '窓壁', '扉枠付きの壁', '壁を外す'] as const) {
            strictEqual(選んだ筆に対応する消しの筆(筆), '壁を外す')
        }
    })

    it('飾りの筆を選んでいるときは飾りを外す', () => {
        for (const 筆 of ['出窓を差し込む', '煙突を立てる', '飾りを外す'] as const) {
            strictEqual(選んだ筆に対応する消しの筆(筆), '飾りを外す')
        }
    })

    it('どの筆を選んでいても、消しの筆は面への筆の並びの中から選ばれる', () => {
        for (const 筆 of 全ての面への筆) {
            strictEqual(全ての面への筆.includes(選んだ筆に対応する消しの筆(筆)), true)
        }
    })
})
