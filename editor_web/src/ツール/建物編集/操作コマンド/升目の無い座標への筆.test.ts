import { strictEqual } from 'node:assert/strict'
import { describe, it } from 'node:test'
import { 建物の格子の編集モデル, 初期の建物の格子を作る } from '../編集モデル/index.ts'
import { 升目への筆が断る理由 } from './升目への筆.ts'

// 升目の無い座標を触ったときに、何も起きないまま黙って終わる筆が残っていないことを確かめる。
// 押しても画面が1つも変わらない操作は、その操作が成立していないのと同じである(エディター制作スキル第5条)。
describe('升目の無い座標への筆の断り', () => {
    const 新しいモデル = (): 建物の格子の編集モデル =>
        建物の格子の編集モデル.契約の値から復元する(初期の建物の格子を作る('grid_building_1', '新しい建物'))

    const 升目の無い座標 = { 横: 1, 奥: 0, 階: 0 }

    it('床と屋根と根の筆は升目の無い座標で断る', () => {
        const モデル = 新しいモデル()
        for (const 筆 of ['床を張る', '床を外す', '屋根を載せる', '屋根を外す', '根にする'] as const) {
            strictEqual(升目への筆が断る理由(モデル, 筆, 升目の無い座標), '升目の無い座標にはこの筆が効かない')
        }
    })

    it('升目のある座標では床と屋根と根の筆を断らない', () => {
        const モデル = 新しいモデル()
        for (const 筆 of ['床を張る', '床を外す', '屋根を載せる', '屋根を外す', '根にする'] as const) {
            strictEqual(升目への筆が断る理由(モデル, 筆, { 横: 0, 奥: 0, 階: 0 }), undefined)
        }
    })

    it('升目を置く筆は升目の無い座標で断らない', () => {
        strictEqual(升目への筆が断る理由(新しいモデル(), '升目を置く', 升目の無い座標), undefined)
    })

    // 平面図の右クリックはこの筆へ結ばれている(左が置く・右が消す)。升目の無い座標での右クリックが
    // 黙って終わらないことを確かめる。
    it('升目を消す筆は升目の無い座標で断る', () => {
        strictEqual(升目への筆が断る理由(新しいモデル(), '升目を消す', 升目の無い座標), '升目の無い座標にはこの筆が効かない')
    })
})
