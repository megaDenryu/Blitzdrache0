import type { 升目の座標 } from '../../../生成/編集資源契約.ts'
import type { 升目を消せない理由, 升目を置けない理由, 建物の格子の編集モデル } from '../編集モデル/index.ts'

// 平面図で升目の中央を触ったときに何が起きるかの選択と、その適用。面へ効く筆は`面への筆`が持つ。
export type 升目への筆 = '升目を置く' | '升目を消す' | '床を張る' | '床を外す' | '屋根を載せる' | '屋根を外す' | '根にする'

export const 全ての升目への筆: readonly 升目への筆[] = [
    '升目を置く',
    '升目を消す',
    '床を張る',
    '床を外す',
    '屋根を載せる',
    '屋根を外す',
    '根にする',
]

// 升目の無い座標を触ったときの断り。床・屋根・根の筆は升目そのものへ効くため、升目が無ければ何も起きない。
// 黙って素通りさせると、押したのに画面が1つも変わらない操作になる(エディター制作スキル第5条)。
export type 升目の無い座標への断り = '升目の無い座標にはこの筆が効かない'

const 升目があってはじめて効く筆: readonly 升目への筆[] = ['床を張る', '床を外す', '屋根を載せる', '屋根を外す', '根にする']

// 触る前に筆が断られる事情を調べる。
export function 升目への筆が断る理由(
    モデル: 建物の格子の編集モデル,
    筆: 升目への筆,
    座標: 升目の座標,
): 升目を置けない理由 | 升目を消せない理由 | 升目の無い座標への断り | undefined {
    if (筆 === '升目を置く') return モデル.升目を置けない理由を調べる(座標)
    // 升目の無い座標での消しをここで断る。消せない理由の判定は「消したあとの格子が成り立つか」だけを
    // 見るため、もともと升目が無い座標では理由なしを返す。黙って素通りさせると、右クリックしたのに
    // 画面が1つも変わらない操作になる(エディター制作スキル第5条)。
    if (筆 === '升目を消す') {
        if (!モデル.升目があるか(座標)) return '升目の無い座標にはこの筆が効かない'
        return モデル.升目を消せない理由を調べる(座標)
    }
    if (升目があってはじめて効く筆.includes(筆) && !モデル.升目があるか(座標)) return '升目の無い座標にはこの筆が効かない'
    return undefined
}

export function 升目への筆を適用する(モデル: 建物の格子の編集モデル, 筆: 升目への筆, 座標: 升目の座標): void {
    switch (筆) {
        case '升目を置く':
            return モデル.升目を置く(座標)
        case '升目を消す':
            return モデル.升目を消す(座標)
        case '床を張る':
            return モデル.床を定める(座標, '張る')
        case '床を外す':
            return モデル.床を定める(座標, '張らない')
        case '屋根を載せる':
            return モデル.屋根を定める(座標, '載せる')
        case '屋根を外す':
            return モデル.屋根を定める(座標, '載せない')
        case '根にする':
            return モデル.根を定める(座標)
    }
}
