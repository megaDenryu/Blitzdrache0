import type { 升目の座標 } from '../../../生成/編集資源契約.ts'
import type { 升目を消せない理由, 升目を置けない理由, 建物の格子の編集モデル } from '../編集モデル/index.ts'

// 平面図で升目の中央を触ったときに何が起きるかの選択と、その適用。面へ効く筆は`面への筆`が持つ。
export type 升目への筆 = '升目を置く' | '升目を消す' | '床を張る' | '床を外す' | '屋根を載せる' | '屋根を外す' | '根にする'

export const 全ての升目への筆: readonly 升目への筆[] = [
    '升目を置く',
    '升目を消す',
    '床を張る',
    '床を外す',
    '屋根を載せる',
    '屋根を外す',
    '根にする',
]

// 触る前に筆が断られる事情を調べる。断るのは升目の置き消しの2つだけであり、残りの筆は効かない場所を
// 黙って素通りする(床や屋根の筆は、升目の無い枠を触っても人が誤りとは受け取らない)。
export function 升目への筆が断る理由(
    モデル: 建物の格子の編集モデル,
    筆: 升目への筆,
    座標: 升目の座標,
): 升目を置けない理由 | 升目を消せない理由 | undefined {
    if (筆 === '升目を置く') return モデル.升目を置けない理由を調べる(座標)
    if (筆 === '升目を消す') return モデル.升目を消せない理由を調べる(座標)
    return undefined
}

export function 升目への筆を適用する(モデル: 建物の格子の編集モデル, 筆: 升目への筆, 座標: 升目の座標): void {
    switch (筆) {
        case '升目を置く':
            return モデル.升目を置く(座標)
        case '升目を消す':
            return モデル.升目を消す(座標)
        case '床を張る':
            return モデル.床を定める(座標, '張る')
        case '床を外す':
            return モデル.床を定める(座標, '張らない')
        case '屋根を載せる':
            return モデル.屋根を定める(座標, '載せる')
        case '屋根を外す':
            return モデル.屋根を定める(座標, '載せない')
        case '根にする':
            return モデル.根を定める(座標)
    }
}
