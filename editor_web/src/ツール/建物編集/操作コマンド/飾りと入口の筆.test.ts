import { deepStrictEqual, strictEqual } from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { 升目の座標 } from '../../../生成/編集資源契約.ts'
import { 初期の建物の格子を作る, 側面のはめ口を読む, 側面から入口方向へ写す, 煙突の段数 } from '../編集モデル/index.ts'
import { 建物編集の操作履歴 } from './建物編集の操作履歴.ts'
import { 面への筆が断る理由, 面への筆を適用する } from './面への筆.ts'

// 壁の外面の飾りの筆と入口の向きの触りが、1回につき1つのコマンドとして積まれ、取り消しで元へ戻ることを確かめる。
describe('飾りと入口の筆', () => {
    const 原点: 升目の座標 = { 横: 0, 奥: 0, 階: 0 }
    const 新しい履歴 = (): 建物編集の操作履歴 => new 建物編集の操作履歴(初期の建物の格子を作る('grid_building_1', '新しい建物'))
    const 原点の正面の飾り = (履歴: 建物編集の操作履歴): unknown => {
        const 宣言 = 履歴.モデル.宣言を引く(原点)
        if (宣言 === undefined) return undefined
        const 値 = 側面のはめ口を読む(宣言, '正面')
        return 値.種類 === '壁を入れる' ? 値.値.外面の飾り : undefined
    }

    it('壁のある面へ出窓を差し込み、取り消すと飾りが戻る', () => {
        const 履歴 = 新しい履歴()
        const 積んだか = 履歴.操作を1つ積む('出窓を差し込む', (モデル) =>
            面への筆を適用する(モデル, '出窓を差し込む', 原点, '正面', 煙突の段数.既定を作る()),
        )
        strictEqual(積んだか, true)
        deepStrictEqual(原点の正面の飾り(履歴), { 種類: '出窓を差し込む' })
        strictEqual(履歴.取り消す(), true)
        deepStrictEqual(原点の正面の飾り(履歴), { 種類: '付けない' })
    })

    it('煙突は選んだ段数で立ち、飾りを外す筆で付けないへ戻る', () => {
        const 履歴 = 新しい履歴()
        const 段数 = 煙突の段数.生成する(3)
        strictEqual(段数 === undefined, false)
        if (段数 === undefined) return
        履歴.操作を1つ積む('煙突を立てる', (モデル) => 面への筆を適用する(モデル, '煙突を立てる', 原点, '正面', 段数))
        deepStrictEqual(原点の正面の飾り(履歴), { 種類: '煙突を立てる', 値: { 段数: 3 } })
        履歴.操作を1つ積む('飾りを外す', (モデル) => 面への筆を適用する(モデル, '飾りを外す', 原点, '正面', 段数))
        deepStrictEqual(原点の正面の飾り(履歴), { 種類: '付けない' })
    })

    it('零段や小数の煙突の段数は作れない', () => {
        strictEqual(煙突の段数.生成する(0), undefined)
        strictEqual(煙突の段数.生成する(1.5), undefined)
        strictEqual(煙突の段数.既定を作る().段数, 1)
    })

    it('壁の無い面への飾りの筆は断られ、格子が変わらない', () => {
        const 履歴 = 新しい履歴()
        履歴.操作を1つ積む('壁を外す', (モデル) => 面への筆を適用する(モデル, '壁を外す', 原点, '正面', 煙突の段数.既定を作る()))
        strictEqual(面への筆が断る理由(履歴.モデル, '出窓を差し込む', 原点, '正面'), '壁の無い面には飾りを付けられない')
        const 積んだか = 履歴.操作を1つ積む('出窓を差し込む', (モデル) =>
            面への筆を適用する(モデル, '出窓を差し込む', 原点, '正面', 煙突の段数.既定を作る()),
        )
        strictEqual(積んだか, false)
    })

    it('入口の向きを変えると1つのコマンドが積まれ、取り消しで既定の向きへ戻る', () => {
        const 履歴 = 新しい履歴()
        deepStrictEqual(履歴.モデル.名乗り.入口のローカル方向, { x: 0, z: 1 })
        const 積んだか = 履歴.操作を1つ積む('入口の向きを変える', (モデル) =>
            モデル.名乗り.入口の方向を定める(側面から入口方向へ写す('右面')),
        )
        strictEqual(積んだか, true)
        deepStrictEqual(履歴.モデル.名乗り.入口のローカル方向, { x: 1, z: 0 })
        strictEqual(履歴.取り消す(), true)
        deepStrictEqual(履歴.モデル.名乗り.入口のローカル方向, { x: 0, z: 1 })
    })
})
