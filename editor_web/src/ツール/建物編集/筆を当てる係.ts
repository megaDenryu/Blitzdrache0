import type { 升目の座標 } from '../../生成/編集資源契約.ts'
import type { 升目の側面 } from './編集モデル/index.ts'
import type { 触りの知らせの札 } from './画面/index.ts'
import {
    升目への筆が断る理由,
    升目への筆を適用する,
    面への筆が断る理由,
    面への筆を適用する,
    type 升目への筆,
    type 面への筆,
} from './操作コマンド/index.ts'
import type { 建物編集の状態 } from './建物編集の状態.ts'

// 名指された筆を升目か面へ当て、断られたらその事情を知らせの札へ出す操作サービス。
// 触るのは編集の状態の操作履歴と、断りを出す札の2つだけであり、画面の他の部品には触れない。
// 筆が断られたら格子を触らず、断りの事情だけを画面へ出す。編集モデルの側も同じ判定で拒むため、
// ここを通らない経路から拒まれる格子が入ることはない。
export class 筆を当てる係 {
    public constructor(
        private readonly _状態: 建物編集の状態,
        private readonly _知らせの札: 触りの知らせの札,
    ) {}

    // 格子が変わったときだけ真を返す。画面の作り直しを起こすかどうかを呼び出し側が決められるようにする。
    public 升目へ当てる(筆: 升目への筆, 座標: 升目の座標): boolean {
        const 断り = 升目への筆が断る理由(this._状態.履歴.モデル, 筆, 座標)
        this.断りを知らせる(筆, 断り)
        if (断り !== undefined) return false
        if (!this._状態.履歴.操作を1つ積む(筆, (モデル) => 升目への筆を適用する(モデル, 筆, 座標))) {
            return this.何も変わらなかったと知らせる(筆)
        }
        this._状態.升目を選ぶ(座標)
        return true
    }

    public 面へ当てる(筆: 面への筆, 座標: 升目の座標, 側面: 升目の側面): boolean {
        const 断り = 面への筆が断る理由(this._状態.履歴.モデル, 筆, 座標, 側面)
        this.断りを知らせる(筆, 断り)
        if (断り !== undefined) return false
        const 段数 = this._状態.選んだ煙突の段数
        if (!this._状態.履歴.操作を1つ積む(筆, (モデル) => 面への筆を適用する(モデル, 筆, 座標, 側面, 段数))) {
            return this.何も変わらなかったと知らせる(筆)
        }
        this._状態.升目を選ぶ(座標)
        return true
    }

    private 断りを知らせる(筆: string, 断り: string | undefined): void {
        this._知らせの札.文言を示す(断り === undefined ? '' : `${筆}: ${断り}`)
    }

    // 断りが無かったのに格子が1つも変わらなかったとき。既にその姿になっている座標を触った場合が
    // これに当たる。黙って終わらせず、変わらなかったことを人へ返す(エディター制作スキル第5条)。
    private 何も変わらなかったと知らせる(筆: string): boolean {
        this._知らせの札.文言を示す(`${筆}: この座標では何も変わらない`)
        return false
    }
}
