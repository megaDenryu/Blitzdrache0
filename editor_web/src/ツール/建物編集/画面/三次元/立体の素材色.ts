import type { 立体の役割 } from '../../編集モデル/index.ts'

// 簡易の形を描くときの素の色。実部品のテクスチャの写しではなく、木・漆喰・瓦・板・石という
// 材の違いが目で分かる程度の色である。識別色ではなくこの色を本体へ塗るのは、識別色だけの立方体では
// 建物の形が読めないと判定されたためである(判断13)。
// 参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断13」
const 役割ごとの素材色: Record<立体の役割, number> = {
    骨格: 0x6b4f31,
    壁: 0xe8e2d4,
    屋根: 0x8e4436,
    床: 0xb59468,
    飾り: 0x9aa0a6,
    入口の印: 0xd08a3c,
}

export function 立体の素材色を引く(役割: 立体の役割): number {
    return 役割ごとの素材色[役割]
}
