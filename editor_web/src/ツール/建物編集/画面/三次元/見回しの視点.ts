import type { 見取りの外接箱 } from '../../編集モデル/index.ts'

// 三次元の識別色表示のカメラの置き場を決める視点。水平の向きと俯角と距離を持ち、
// 建物ぜんたいが画面へ収まる距離を外接箱から求める。
//
// 自由な軌道操作を持たせないのは、この表示の役目が「どの役割の部品がどこに在るか」を確かめることだけであり、
// 絵の判断はエンジンで実際に歩いて行う(判断9)ためである。人が回すのは水平の8方位だけでよい。
const 方位の刻み = Math.PI / 4

const 俯角ラジアン = Math.PI / 6

// 外接箱の対角に掛けて距離にする係数。1より大きくして、建物の端が画面の縁へ触れないようにする。
const 距離の余裕 = 1.3

export interface カメラの置き場 {
    readonly 位置メートル: { x: number; y: number; z: number }
    readonly 注視点メートル: { x: number; y: number; z: number }
}

export class 見回しの視点 {
    private _方位の段数 = 1

    public 左へ回す(): void {
        this._方位の段数 -= 1
    }

    public 右へ回す(): void {
        this._方位の段数 += 1
    }

    public 置き場を求める(外接箱: 見取りの外接箱): カメラの置き場 {
        const 方位 = this._方位の段数 * 方位の刻み
        const 距離 = 外接箱.対角の長さメートル * 距離の余裕
        const 水平距離 = 距離 * Math.cos(俯角ラジアン)
        return {
            位置メートル: {
                x: 外接箱.中心メートル.x + 水平距離 * Math.sin(方位),
                y: 外接箱.中心メートル.y + 距離 * Math.sin(俯角ラジアン),
                z: 外接箱.中心メートル.z + 水平距離 * Math.cos(方位),
            },
            注視点メートル: 外接箱.中心メートル,
        }
    }
}
