import type { CanvasC } from 'sengen-ui'
import type { レイキャスト入力, 透視カメラ, 部品交差情報 } from 'SengenThree'
import type { 升目の座標 } from '../../../../生成/編集資源契約.ts'
import {
    ホイールと右クリックを配線する,
    人の操作を覚えるカメラ制御,
    注視点の印を出さない表示制御,
    視点のポインタ操作係,
    軌道カメラ制御器,
} from '../../../../三次元の視点操作/index.ts'
import type { 建物の立体メッシュ部品 } from './建物の立体メッシュ部品.ts'

export interface I三次元の触り {
    readonly on升目を選ぶ: (座標: 升目の座標) => void
}

// 入力を配線する相手。三次元パネルが持つ部品のうち、ポインタの配線が触るものだけを口にする。
export interface 建物の三次元の入力先 {
    readonly キャンバス要素: CanvasC
    readonly カメラ: 透視カメラ
    readonly カメラ制御: 軌道カメラ制御器
    readonly レイキャスト: レイキャスト入力
    readonly 立体: 建物の立体メッシュ部品
}

// 建物の三次元表示のポインタ入力を配線し、購読の生死を持つ操作サービス。
// 視点の操作(右ドラッグ=回転・中ドラッグ=平行移動・ホイール=寄り引き)は`三次元の視点操作`の共通の
// 割り当てへ丸ごと預け、この型が決めるのは左クリックが升目の選択になることだけである。
// 参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断13」
export class 建物の三次元の入力係 {
    private readonly _カメラ制御: 人の操作を覚えるカメラ制御
    private readonly _ホイールと右クリックの解除: () => void

    public constructor(
        private readonly _先: 建物の三次元の入力先,
        触り: I三次元の触り,
    ) {
        this._カメラ制御 = new 人の操作を覚えるカメラ制御(_先.カメラ制御)
        const 視点 = new 視点のポインタ操作係({
            カメラ制御: this._カメラ制御,
            注視点表示制御: new 注視点の印を出さない表示制御(),
        })
        _先.レイキャスト.配線する({
            押し時: ({ 原初事象 }) => 視点.押された(原初事象),
            離し時: ({ 原初事象 }) => 視点.離された(原初事象),
            移動時: ({ 原初事象 }) => {
                視点.視点の操作として動かしたか(原初事象)
            },
            クリック時: ({ 当たり一覧, 原初事象 }) => this.クリックされた(当たり一覧, 原初事象, 触り),
        })
        _先.レイキャスト.キャンバスの購読を開始する({
            キャンバス: _先.キャンバス要素.dom.element,
            カメラ: _先.カメラ,
            対象部品一覧: [_先.立体],
        })
        this._ホイールと右クリックの解除 = ホイールと右クリックを配線する({
            キャンバス要素: _先.キャンバス要素,
            カメラ制御: this._カメラ制御,
        })
    }

    // 人が一度でも視点を動かしたら、以後は形が変わっても勝手に写し直さない。
    public get 視点を人が動かしたか(): boolean {
        return this._カメラ制御.人が動かしたか
    }

    public 解除する(): void {
        this._先.レイキャスト.キャンバスの購読を解除する()
        this._ホイールと右クリックの解除()
    }

    // 手前から順に見て、最初に升目へ結び付いた当たりを選ぶ。最前面だけを見ると、選択の枠のように
    // 升目に属さない立体が手前へ来たときにクリックが吸われ、奥の升目を選べなくなる。
    private クリックされた(当たり一覧: readonly 部品交差情報[], 原初事象: MouseEvent, 触り: I三次元の触り): void {
        if (原初事象.button !== 0) return
        for (const 当たり of 当たり一覧) {
            const 座標 = this._先.立体.触られた升目を引く(当たり.部品)
            if (座標 !== undefined) {
                触り.on升目を選ぶ(座標)
                return
            }
        }
    }
}
