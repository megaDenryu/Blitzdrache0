import type { 部品の役割 } from '../../編集モデル/index.ts'

// 部品の役割ごとの識別色。実部品のテクスチャや材質を写した色ではなく、役割を見分けるためだけの色である
// (判断9: 三次元表示は識別色で足り、絵の真実はエンジンが担う)。
// 色相を役割ごとに大きく離すのは、隣り合う板がどちらの役割かを人が一目で分けられるようにするためである。
const 役割ごとの色: Record<部品の役割, number> = {
    骨格: 0x94a3b8,
    壁: 0xf1f5f9,
    屋根: 0xdc2626,
    床: 0xca8a04,
    飾り: 0x22c55e,
}

export function 役割の識別色を引く(役割: 部品の役割): number {
    return 役割ごとの色[役割]
}

// 骨格だけを線の枠で描くのは、面のある箱にすると中の床と壁が見えなくなるためである。
export function 線の枠で描く役割か(役割: 部品の役割): boolean {
    return 役割 === '骨格'
}
