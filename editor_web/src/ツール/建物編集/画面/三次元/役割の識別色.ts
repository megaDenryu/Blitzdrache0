import type { 立体の役割 } from '../../編集モデル/index.ts'

// 立体の役割ごとの識別色。物体そのものの色ではなく、役割を見分けるためだけの重ね表示の色である
// (判断13: 形が見える表示を土台にし、識別色は意味を補う重ねへ下げる)。
// 色相を役割ごとに大きく離すのは、隣り合う板がどちらの役割かを人が一目で分けられるようにするためである。
// 参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断13」
const 役割ごとの色: Record<立体の役割, number> = {
    骨格: 0x38bdf8,
    壁: 0xf1f5f9,
    屋根: 0xdc2626,
    床: 0xca8a04,
    飾り: 0x22c55e,
    入口の印: 0xf97316,
}

export function 役割の識別色を引く(役割: 立体の役割): number {
    return 役割ごとの色[役割]
}
