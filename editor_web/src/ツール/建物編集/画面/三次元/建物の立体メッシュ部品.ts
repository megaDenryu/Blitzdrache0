import { BoxGeometry, type Material } from 'three'
import { グループ, メッシュ部品, 基本マテリアルを作る, 標準マテリアルを作る } from 'SengenThree'
import type { 部品の役割, 表示する立体 } from '../../編集モデル/index.ts'
import { 役割の識別色を引く, 線の枠で描く役割か } from './役割の識別色.ts'

// 立体の見取りを識別色のメッシュ群として描く部品。役割ごとの材質を1つずつ持ち回し、
// 見取りが変わるたびにメッシュを作り直す。
//
// 作り直すのは、升目を1つ触るだけで隣の升目の壁と真下の屋根まで変わり、変わった立体だけを数え上げると
// 編集モデルの整えと二重管理になるためである。格子1件の立体は数百の規模であり、人の操作1回に対して
// 作り直しの費用は問題にならない。
export class 建物の立体メッシュ部品 extends グループ {
    private readonly _役割ごとの材質 = new Map<部品の役割, Material>()
    private _描いたメッシュ一覧: メッシュ部品[] = []

    public 見取りを描き直す(見取り: readonly 表示する立体[]): void {
        for (const メッシュ of this._描いたメッシュ一覧) メッシュ.破棄する()
        this._描いたメッシュ一覧 = 見取り.map((立体) => this.立体を1つ描く(立体))
        this.childs(this._描いたメッシュ一覧)
    }

    private 立体を1つ描く(立体: 表示する立体): メッシュ部品 {
        const 幾何 = new BoxGeometry(立体.大きさメートル.x, 立体.大きさメートル.y, 立体.大きさメートル.z)
        const 材質 = this.役割の材質を引く(立体.役割)
        const メッシュ = new メッシュ部品(幾何, 材質)
        // 注意: メッシュ部品は渡された材質を自分の台帳へ登録するが、材質はこの部品が役割ごとに1つだけ持つ
        // 共有物である。登録を外さないと、見取りを描き直すたびに共有の材質が壊れる。
        メッシュ.資源台帳.解除する(材質)
        メッシュ.実体.position.set(立体.中心メートル.x, 立体.中心メートル.y, 立体.中心メートル.z)
        メッシュ.実体.rotation.x = 立体.x軸まわりの傾きラジアン
        return メッシュ
    }

    private 役割の材質を引く(役割: 部品の役割): Material {
        const 既にある材質 = this._役割ごとの材質.get(役割)
        if (既にある材質 !== undefined) return 既にある材質
        const 色 = 役割の識別色を引く(役割)
        const 材質 = 線の枠で描く役割か(役割)
            ? 基本マテリアルを作る({ 色, ワイヤーフレームか: true })
            : 標準マテリアルを作る({ 色, 粗さ: 0.85, 金属度: 0, 両面描画か: true })
        this._役割ごとの材質.set(役割, 材質)
        this.資源台帳.登録する(材質)
        return 材質
    }
}
