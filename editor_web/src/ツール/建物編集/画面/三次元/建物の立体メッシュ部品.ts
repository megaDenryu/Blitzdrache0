import { BoxGeometry, type Material } from 'three'
import { グループ, メッシュ部品, type 三次元部品 } from 'SengenThree'
import type { 升目の座標 } from '../../../../生成/編集資源契約.ts'
import type { 表示する立体 } from '../../編集モデル/index.ts'
import { 立体の材質台帳 } from './立体の材質台帳.ts'
import { 選んだ升目の枠部品 } from './選んだ升目の枠部品.ts'

// 立体の見取りをメッシュ群として描く部品。素の材の色で本体を描き、求めがあれば同じ形へ役割の識別色の
// 線の枠を重ねる(判断13)。どのメッシュがどの升目のものかを索引に持ち、三次元で触った先の升目を引けるようにする。
//
// 見取りが変わるたびに作り直すのは、升目を1つ触るだけで隣の升目の壁と真下の屋根まで変わり、
// 変わった立体だけを数え上げると編集モデルの整えと二重管理になるためである。
// 参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断13」
export class 建物の立体メッシュ部品 extends グループ {
    private readonly _材質台帳 = new 立体の材質台帳()
    private readonly _選択の枠 = new 選んだ升目の枠部品()
    private _描いたメッシュ一覧: メッシュ部品[] = []
    private _メッシュごとの升目 = new Map<三次元部品, 升目の座標>()

    public constructor() {
        super()
        for (const 材質 of this._材質台帳.全ての材質を数え上げる()) this.資源台帳.登録する(材質)
        this.child(this._選択の枠)
    }

    public 見取りを描き直す(見取り: readonly 表示する立体[], 識別色を重ねるか: boolean): void {
        for (const メッシュ of this._描いたメッシュ一覧) メッシュ.破棄する()
        this._メッシュごとの升目 = new Map()
        this._描いたメッシュ一覧 = 見取り.flatMap((立体) => this.立体を1つ描く(立体, 識別色を重ねるか))
        this.childs(this._描いたメッシュ一覧)
    }

    public 選んだ升目を示す(座標: 升目の座標 | undefined): void {
        this._選択の枠.選んだ升目へ移す(座標)
    }

    // 三次元で触った部品が属する升目。建物の立体ではないもの(選択の枠)を触ったときは「無し」を返す。
    public 触られた升目を引く(部品: 三次元部品): 升目の座標 | undefined {
        return this._メッシュごとの升目.get(部品)
    }

    private 立体を1つ描く(立体: 表示する立体, 識別色を重ねるか: boolean): メッシュ部品[] {
        const 本体 = this.姿を1つのメッシュにする(立体, this._材質台帳.素材の材質を引く(立体.役割))
        if (!識別色を重ねるか) return [本体]
        return [本体, this.姿を1つのメッシュにする(立体, this._材質台帳.識別色の材質を引く(立体.役割))]
    }

    private 姿を1つのメッシュにする(立体: 表示する立体, 材質: Material): メッシュ部品 {
        const 大きさ = 立体.姿.大きさメートル
        const メッシュ = new メッシュ部品(new BoxGeometry(大きさ.x, 大きさ.y, 大きさ.z), 材質)
        // 注意: メッシュ部品は渡された材質を自分の台帳へ登録するが、材質は材質台帳が持つ共有物である。
        // 登録を外さないと、見取りを描き直すたびに共有の材質が壊れる。
        メッシュ.資源台帳.解除する(材質)
        メッシュ.実体.position.set(立体.中心メートル.x, 立体.中心メートル.y, 立体.中心メートル.z)
        if (立体.姿.種類 === '傾いた板') メッシュ.実体.rotation.x = 立体.姿.x軸まわりの傾きラジアン
        this._メッシュごとの升目.set(メッシュ, 立体.属する升目の座標)
        return メッシュ
    }
}
