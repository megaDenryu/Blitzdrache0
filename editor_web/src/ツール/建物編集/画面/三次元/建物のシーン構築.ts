import { 場面を作る, 半球光源を作る, 平行光源を作る, 環境光を作る, 透視カメラを作る } from 'SengenThree'
import { 軌道カメラ制御器 } from '../../../../三次元の視点操作/index.ts'
import { 建物の立体メッシュ部品 } from './建物の立体メッシュ部品.ts'

// 建物の三次元表示のシーングラフを組み立てる工程。呼び出し元(建物の三次元パネル)はキャンバス・描画ループ・
// 入力・破棄の管理だけを担い、シーンの内訳の組み立てはここへ閉じる。
// チャンク編集の三次元ビューが`三次元ビュー部品/シーン構築.ts`へ同じ切り方をしているのに倣う。

const 背景色 = 0x0b0f19

// 建物1件はさしわたし数メートルであるため、寄り引きの幅を地形のビューよりずっと狭く取る。
const カメラの初期距離メートル = 12

const カメラの最小距離メートル = 1.5

const カメラの最大距離メートル = 120

export interface 建物のシーン部品束 {
    readonly 場面: ReturnType<typeof 場面を作る>
    readonly カメラ: ReturnType<typeof 透視カメラを作る>
    readonly カメラ制御: 軌道カメラ制御器
    readonly 立体: 建物の立体メッシュ部品
}

export function 建物のシーンを構築する(): 建物のシーン部品束 {
    const カメラ = 透視カメラを作る({ 画角: 45, アスペクト比: 16 / 9, 手前クリップ距離: 0.05, 奥クリップ距離: 500 })
    const 立体 = new 建物の立体メッシュ部品()
    const 場面 = 場面を作る()
        .背景色を設定する(背景色)
        .childs([
            カメラ,
            環境光を作る({ 色: 0xe2e8f0, 強さ: 0.45 }),
            半球光源を作る({ 空の色: 0xbfdbfe, 地面の色: 0x4b5563, 強さ: 0.55 }),
            平行光源を作る({ 色: 0xffedd5, 強さ: 1.1 }).位置を設定する(12, 20, 8),
            立体,
        ])
    const カメラ制御 = new 軌道カメラ制御器(
        カメラ,
        カメラの初期距離メートル,
        カメラの最小距離メートル,
        カメラの最大距離メートル,
    )
    return { 場面, カメラ, カメラ制御, 立体 }
}
