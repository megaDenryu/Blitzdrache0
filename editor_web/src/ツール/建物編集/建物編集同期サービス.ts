import type { 建物の格子接続 } from '../../境界/通信/index.ts'
import type { 升目の座標 } from '../../生成/編集資源契約.ts'
import type { 升目の側面 } from './編集モデル/index.ts'
import type { 建物編集画面 } from './画面/index.ts'
import { 升目への筆を適用する, 面への筆を適用する } from './操作コマンド/index.ts'
import type { 建物編集の状態 } from './建物編集の状態.ts'
import { 建物の格子の永続化係 } from './建物の格子の永続化係.ts'

// 画面と編集の状態と保管庫の接続を保持し、触り・取り消し・保存・読み直しをメソッドで公開する操作サービス。
// 依存を保持させるのは、どの操作もこの3つを同時に使うためであり、画面の出来事ごとに引数で運ばせると
// 別の建物の状態を渡しても型が通るためである。
export class 建物編集同期サービス {
    private readonly _永続化: 建物の格子の永続化係

    public constructor(
        private readonly _画面: 建物編集画面,
        private readonly _状態: 建物編集の状態,
        接続: 建物の格子接続,
    ) {
        this._永続化 = new 建物の格子の永続化係(_画面, _状態, 接続)
    }

    public get 永続化(): 建物の格子の永続化係 {
        return this._永続化
    }

    // 画面の出来事をこのサービスのメソッドへ結ぶ。1回だけ呼ぶ(押すたびに購読が積み増るのを避ける)。
    public 画面の出来事を配線する(): void {
        this._画面.取り消しボタン.onClick(() => this.取り消す())
        this._画面.やり直しボタン.onClick(() => this.やり直す())
        this._画面.表示名入力.onChange(() => this.表示名を変える())
        this._画面.永続化.on保存クリック(() => void this._永続化.保存する())
        this._画面.永続化.on読込クリック(() => void this._永続化.読み直す(() => this.表示を作り直す()))
    }

    // 平面図・筆・階の切替・活性表示を、いまの状態から作り直す。1回の触りで隣と真下の升目の継ぎ目まで
    // 変わるため、変わった箇所だけを差し替えず全体を作り直す(格子1件の升目は数十の規模である)。
    public 表示を作り直す(): void {
        this._画面.階の切替.再構築する(this._状態.最上階(), this._状態.選んだ階, {
            on階を選ぶ: (階) => {
                this._状態.階を選ぶ(階)
                this.表示を作り直す()
            },
        })
        this._画面.筆.再構築する(this._状態.選んだ升目への筆, this._状態.選んだ面への筆, {
            on升目への筆を選ぶ: (筆) => {
                this._状態.升目への筆を選ぶ(筆)
                this.表示を作り直す()
            },
            on面への筆を選ぶ: (筆) => {
                this._状態.面への筆を選ぶ(筆)
                this.表示を作り直す()
            },
        })
        this._画面.平面図.再構築する(this._状態.履歴.モデル, this._状態.選んだ階, {
            on升目を触る: (座標) => this.升目を触る(座標),
            on面を触る: (座標, 側面) => this.面を触る(座標, 側面),
        })
        this._画面.取り消しとやり直しの活性を更新する(this._状態.履歴.取り消せるか, this._状態.履歴.やり直せるか)
    }

    private 升目を触る(座標: 升目の座標): void {
        const 筆 = this._状態.選んだ升目への筆
        this._状態.履歴.操作を1つ積む(筆, (モデル) => 升目への筆を適用する(モデル, 筆, 座標))
        this.表示を作り直す()
    }

    private 面を触る(座標: 升目の座標, 側面: 升目の側面): void {
        const 筆 = this._状態.選んだ面への筆
        this._状態.履歴.操作を1つ積む(筆, (モデル) => 面への筆を適用する(モデル, 筆, 座標, 側面))
        this.表示を作り直す()
    }

    private 取り消す(): void {
        this._状態.履歴.取り消す()
        this.表示を作り直す()
    }

    private やり直す(): void {
        this._状態.履歴.やり直す()
        this.表示を作り直す()
    }

    private 表示名を変える(): void {
        const 表示名 = this._画面.表示名入力.getValue()
        this._状態.履歴.操作を1つ積む('表示名を変える', (モデル) => モデル.表示名を定める(表示名))
        this._画面.取り消しとやり直しの活性を更新する(this._状態.履歴.取り消せるか, this._状態.履歴.やり直せるか)
    }
}
