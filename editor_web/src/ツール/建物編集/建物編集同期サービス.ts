import type { 配線ポート } from 'sengen-ui'
import type { 建物の格子接続 } from '../../境界/通信/index.ts'
import type { 升目の座標 } from '../../生成/編集資源契約.ts'
import { 表示名の編集をまとめる係, type I表示名の編集の届け先 } from '../../文書の表示名の編集/index.ts'
import { 側面から入口方向へ写す, type 升目の側面, type 煙突の段数 } from './編集モデル/index.ts'
import type { 建物編集画面 } from './画面/index.ts'
import { 選んだ筆に対応する消しの筆, type 升目への筆, type 面への筆 } from './操作コマンド/index.ts'
import type { 建物編集の状態 } from './建物編集の状態.ts'
import { 建物編集の表示係, type I建物の表示名の届け先, type I建物編集の触り } from './建物編集の表示係.ts'
import { 建物の格子の永続化係 } from './建物の格子の永続化係.ts'
import { 筆を当てる係 } from './筆を当てる係.ts'

// 画面と編集の状態と保管庫の接続を保持し、触り・取り消し・保存・読み直しをメソッドで公開する操作サービス。
// 依存を保持させるのは、どの操作もこの3つを同時に使うためであり、画面の出来事ごとに引数で運ばせると
// 別の建物の状態を渡しても型が通るためである。画面の作り直しそのものは表示係が受け持つ。
export class 建物編集同期サービス implements I建物編集の触り, I表示名の編集の届け先 {
    private readonly _永続化: 建物の格子の永続化係
    private readonly _表示係: 建物編集の表示係
    private readonly _筆: 筆を当てる係
    private readonly _表示名の編集: 表示名の編集をまとめる係

    public constructor(
        private readonly _画面: 建物編集画面,
        private readonly _状態: 建物編集の状態,
        接続: 建物の格子接続,
        private readonly _表示名の届け先: 配線ポート<I建物の表示名の届け先>,
    ) {
        this._永続化 = new 建物の格子の永続化係(_画面, _状態, 接続)
        // 係へ this を渡せるのは、係が受け取った届け先を保持するだけで構築時には1つも呼ばないためである。
        this._表示名の編集 = new 表示名の編集をまとめる係(_状態.履歴.モデル.名乗り.表示名, this)
        this._表示係 = new 建物編集の表示係(_画面, _状態, this._表示名の編集)
        this._筆 = new 筆を当てる係(_状態, _画面.部品.触りの知らせ)
    }

    public get 永続化(): 建物の格子の永続化係 {
        return this._永続化
    }

    public 表示を作り直す(): void {
        this._表示係.作り直す(this)
    }

    // 三次元で触った升目を選ぶ。選んだ升目の階を平面図へ出すため、平面図の見えも一緒に変わる。
    public 升目を選ぶ(座標: 升目の座標): void {
        this._状態.升目を選ぶ(座標)
        this.表示を作り直す()
    }

    public 識別色の重ねを切り替える(): void {
        this._状態.識別色の重ねを切り替える()
        this.表示を作り直す()
    }

    public 建物ぜんたいを写す(): void {
        this._画面.部品.三次元.建物ぜんたいを写す()
    }

    public 階を選ぶ(階: number): void {
        this._状態.階を選ぶ(階)
        this.表示を作り直す()
    }

    public 升目への筆を選ぶ(筆: 升目への筆): void {
        this._状態.升目への筆を選ぶ(筆)
        this.表示を作り直す()
    }

    public 面への筆を選ぶ(筆: 面への筆): void {
        this._状態.面への筆を選ぶ(筆)
        this.表示を作り直す()
    }

    public 煙突の段数を選ぶ(段数: 煙突の段数): void {
        this._状態.煙突の段数を選ぶ(段数)
        this.表示を作り直す()
    }

    public 入口の向く面を選ぶ(側面: 升目の側面): void {
        const 方向 = 側面から入口方向へ写す(側面)
        this._状態.履歴.操作を1つ積む('入口の向きを変える', (モデル) => モデル.名乗り.入口の方向を定める(方向))
        this.表示を作り直す()
    }

    // 平面図で升目の中央を左クリックしたとき。選んでいる筆をその座標へ当てる。
    public 升目を触る(座標: 升目の座標): void {
        if (this._筆.升目へ当てる(this._状態.選んだ升目への筆, 座標)) this.表示を作り直す()
    }

    // 平面図で升目の中央を右クリックしたとき。楽曲の打ち込みと同じく、右は消す側である。
    public 升目を消す(座標: 升目の座標): void {
        if (this._筆.升目へ当てる('升目を消す', 座標)) this.表示を作り直す()
    }

    public 面を触る(座標: 升目の座標, 側面: 升目の側面): void {
        if (this._筆.面へ当てる(this._状態.選んだ面への筆, 座標, 側面)) this.表示を作り直す()
    }

    // 選んでいる筆が飾りの筆なら飾りを、壁の筆なら壁を外す。左で置いたものが右で消える対応にする。
    public 面を消す(座標: 升目の座標, 側面: 升目の側面): void {
        const 筆 = 選んだ筆に対応する消しの筆(this._状態.選んだ面への筆)
        if (this._筆.面へ当てる(筆, 座標, 側面)) this.表示を作り直す()
    }

    public 取り消す(): void {
        this._状態.履歴.取り消す()
        this.表示を作り直す()
    }

    public やり直す(): void {
        this._状態.履歴.やり直す()
        this.表示を作り直す()
    }

    // 名前の欄へ1文字打たれたとき。正本は変えず、文書タブの見出しだけを追随させる(判断13)。
    public 表示名が入力された(入力中の表示名: string): void {
        this._表示名の編集.表示名が入力された(入力中の表示名)
    }

    // 名前の欄から離れたとき。ここで初めて取り消し1回ぶんのコマンドを積む。
    public 表示名が決まった(新しい表示名: string): void {
        this._表示名の編集.表示名の入力が決まった(新しい表示名)
    }

    // I表示名の編集の届け先: 正本を変えずに見えだけを合わせる先は、文書タブの見出しである。
    public 表示名の見えを合わせる(表示名: string): void {
        if (this._表示名の届け先.配線済みか) this._表示名の届け先.先.表示名が変わった(表示名)
    }

    // I表示名の編集の届け先: 入力が決まったときだけ通る、正本を変える1つの経路。
    public 表示名を変えるコマンドを積む(新しい表示名: string): void {
        this._状態.履歴.操作を1つ積む('表示名を変える', (モデル) => モデル.名乗り.表示名を定める(新しい表示名))
        this.表示を作り直す()
    }
}
