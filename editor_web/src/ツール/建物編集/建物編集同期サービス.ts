import type { 建物の格子接続 } from '../../境界/通信/index.ts'
import type { 升目の座標 } from '../../生成/編集資源契約.ts'
import { 側面から入口方向へ写す, type 升目の側面, type 煙突の段数 } from './編集モデル/index.ts'
import type { 建物編集画面 } from './画面/index.ts'
import { 升目への筆が断る理由, 升目への筆を適用する, 面への筆が断る理由, 面への筆を適用する, type 升目への筆, type 面への筆 } from './操作コマンド/index.ts'
import type { 建物編集の状態 } from './建物編集の状態.ts'
import { 建物編集の表示係, type I建物編集の触り } from './建物編集の表示係.ts'
import { 建物の格子の永続化係 } from './建物の格子の永続化係.ts'

// 画面と編集の状態と保管庫の接続を保持し、触り・取り消し・保存・読み直しをメソッドで公開する操作サービス。
// 依存を保持させるのは、どの操作もこの3つを同時に使うためであり、画面の出来事ごとに引数で運ばせると
// 別の建物の状態を渡しても型が通るためである。画面の作り直しそのものは表示係が受け持つ。
export class 建物編集同期サービス implements I建物編集の触り {
    private readonly _永続化: 建物の格子の永続化係
    private readonly _表示係: 建物編集の表示係

    public constructor(
        private readonly _画面: 建物編集画面,
        private readonly _状態: 建物編集の状態,
        接続: 建物の格子接続,
    ) {
        this._永続化 = new 建物の格子の永続化係(_画面, _状態, 接続)
        this._表示係 = new 建物編集の表示係(_画面, _状態)
    }

    public get 永続化(): 建物の格子の永続化係 {
        return this._永続化
    }

    public 表示を作り直す(): void {
        this._表示係.作り直す(this)
    }

    // 三次元で触った升目を選ぶ。選んだ升目の階を平面図へ出すため、平面図の見えも一緒に変わる。
    public 升目を選ぶ(座標: 升目の座標): void {
        this._状態.升目を選ぶ(座標)
        this.表示を作り直す()
    }

    public 識別色の重ねを切り替える(): void {
        this._状態.識別色の重ねを切り替える()
        this.表示を作り直す()
    }

    public 階を選ぶ(階: number): void {
        this._状態.階を選ぶ(階)
        this.表示を作り直す()
    }

    public 升目への筆を選ぶ(筆: 升目への筆): void {
        this._状態.升目への筆を選ぶ(筆)
        this.表示を作り直す()
    }

    public 面への筆を選ぶ(筆: 面への筆): void {
        this._状態.面への筆を選ぶ(筆)
        this.表示を作り直す()
    }

    public 煙突の段数を選ぶ(段数: 煙突の段数): void {
        this._状態.煙突の段数を選ぶ(段数)
        this.表示を作り直す()
    }

    public 入口の向く面を選ぶ(側面: 升目の側面): void {
        const 方向 = 側面から入口方向へ写す(側面)
        this._状態.履歴.操作を1つ積む('入口の向きを変える', (モデル) => モデル.名乗り.入口の方向を定める(方向))
        this.表示を作り直す()
    }

    // 筆が断られたら格子を触らず、断りの事情だけを画面へ出す。編集モデルの側も同じ判定で拒むため、
    // ここを通らない経路から拒まれる格子が入ることはない。
    public 升目を触る(座標: 升目の座標): void {
        const 筆 = this._状態.選んだ升目への筆
        const 断り = 升目への筆が断る理由(this._状態.履歴.モデル, 筆, 座標)
        this._画面.触りの知らせを更新する(断り === undefined ? '' : `${筆}: ${断り}`)
        if (断り !== undefined) return
        this._状態.履歴.操作を1つ積む(筆, (モデル) => 升目への筆を適用する(モデル, 筆, 座標))
        this._状態.升目を選ぶ(座標)
        this.表示を作り直す()
    }

    public 面を触る(座標: 升目の座標, 側面: 升目の側面): void {
        const 筆 = this._状態.選んだ面への筆
        const 断り = 面への筆が断る理由(this._状態.履歴.モデル, 筆, 座標, 側面)
        this._画面.触りの知らせを更新する(断り === undefined ? '' : `${筆}: ${断り}`)
        if (断り !== undefined) return
        const 段数 = this._状態.選んだ煙突の段数
        this._状態.履歴.操作を1つ積む(筆, (モデル) => 面への筆を適用する(モデル, 筆, 座標, 側面, 段数))
        this._状態.升目を選ぶ(座標)
        this.表示を作り直す()
    }

    public 取り消す(): void {
        this._状態.履歴.取り消す()
        this.表示を作り直す()
    }

    public やり直す(): void {
        this._状態.履歴.やり直す()
        this.表示を作り直す()
    }

    public 表示名を変える(): void {
        const 表示名 = this._画面.表示名入力.getValue()
        this._状態.履歴.操作を1つ積む('表示名を変える', (モデル) => モデル.名乗り.表示名を定める(表示名))
        this.表示を作り直す()
    }
}
