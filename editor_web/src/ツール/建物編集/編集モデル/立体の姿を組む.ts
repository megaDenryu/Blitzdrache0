import type { 升目の座標 } from '../../../生成/編集資源契約.ts'
import type { 三次元の寸法, 立体の役割, 表示する立体 } from './建物の立体の見取り.ts'

// 表示する立体を1つ作る工程。姿の判別共用体を組む場所をここ1つに閉じるのは、
// 実部品のモデルを配る経路ができたときに枝を足す場所を1つにするためである。

export function 箱の立体を作る(
    役割: 立体の役割,
    属する升目の座標: 升目の座標,
    中心メートル: 三次元の寸法,
    大きさメートル: 三次元の寸法,
): 表示する立体 {
    return { 役割, 属する升目の座標, 中心メートル, 姿: { 種類: '直方体', 大きさメートル } }
}

export function 傾いた板の立体を作る(
    役割: 立体の役割,
    属する升目の座標: 升目の座標,
    中心メートル: 三次元の寸法,
    大きさメートル: 三次元の寸法,
    x軸まわりの傾きラジアン: number,
): 表示する立体 {
    return {
        役割,
        属する升目の座標,
        中心メートル,
        姿: { 種類: '傾いた板', 大きさメートル, x軸まわりの傾きラジアン },
    }
}
