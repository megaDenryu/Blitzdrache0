import type { 升目の宣言 } from '../../../生成/編集資源契約.ts'
import { 升目1つの立体を数え上げる } from './升目1つの立体.ts'
import { ベイの奥行メートル, ベイの横幅メートル, 階の高さメートル } from './ベイの寸法.ts'

// 三次元の識別色表示が描く立体1つと、その一覧の組み立て。三次元の部品から分けるのは、
// ここが位置と大きさだけを決める純粋な計算であり、three.jsの型を1つも知らないためである。
// 実部品のglbは配信しない(判断9)ため、この見取りは部品の姿ではなく、部品の役割と占める場所を見せる。

export const 全ての部品の役割 = ['骨格', '壁', '屋根', '床', '飾り'] as const

export type 部品の役割 = (typeof 全ての部品の役割)[number]

export interface 三次元の寸法 {
    readonly x: number
    readonly y: number
    readonly z: number
}

// 表示する立体とは、識別色の三次元表示が1つ描く直方体のことである。骨格だけは線の枠として描き、
// 残りは面のある箱として描く。どちらで描くかは役割から決まるため、この型は形を持たない。
export interface 表示する立体 {
    readonly 役割: 部品の役割
    readonly 中心メートル: 三次元の寸法
    readonly 大きさメートル: 三次元の寸法
    // x軸まわりの傾き。屋根の2枚の勾配だけが零でない。
    readonly x軸まわりの傾きラジアン: number
}

export function 立体の見取りを組み立てる(升目一覧: readonly 升目の宣言[]): 表示する立体[] {
    return 升目一覧.flatMap(升目1つの立体を数え上げる)
}

// 見取り全体を収める外接箱の中心と対角の長さ。カメラをどこへ置けば建物ぜんたいが写るかを決めるのに使う。
export interface 見取りの外接箱 {
    readonly 中心メートル: 三次元の寸法
    readonly 対角の長さメートル: number
}

export function 見取りの外接箱を求める(見取り: readonly 表示する立体[]): 見取りの外接箱 {
    if (見取り.length === 0) return 升目1つぶんの外接箱()
    const 最小 = 各軸の端を求める(見取り, -1)
    const 最大 = 各軸の端を求める(見取り, 1)
    const 差 = { x: 最大.x - 最小.x, y: 最大.y - 最小.y, z: 最大.z - 最小.z }
    return {
        中心メートル: { x: (最小.x + 最大.x) / 2, y: (最小.y + 最大.y) / 2, z: (最小.z + 最大.z) / 2 },
        対角の長さメートル: Math.sqrt(差.x * 差.x + 差.y * 差.y + 差.z * 差.z),
    }
}

// 升目が1つも無い格子でもカメラの置き場が決まるようにする。1ベイぶんの箱を原点へ据えた形である。
function 升目1つぶんの外接箱(): 見取りの外接箱 {
    const 差 = { x: ベイの横幅メートル, y: 階の高さメートル, z: ベイの奥行メートル }
    return {
        中心メートル: { x: 0, y: 階の高さメートル / 2, z: 0 },
        対角の長さメートル: Math.sqrt(差.x * 差.x + 差.y * 差.y + 差.z * 差.z),
    }
}

// 符号が正なら各軸の最大、負なら最小を返す。傾きは外接箱の見積もりに入れない(勾配の分だけ小さめに出る)。
function 各軸の端を求める(見取り: readonly 表示する立体[], 符号: number): 三次元の寸法 {
    const 端 = (軸: 'x' | 'y' | 'z'): number => {
        const 値一覧 = 見取り.map((立体) => 立体.中心メートル[軸] + (符号 * 立体.大きさメートル[軸]) / 2)
        return 符号 > 0 ? Math.max(...値一覧) : Math.min(...値一覧)
    }
    return { x: 端('x'), y: 端('y'), z: 端('z') }
}
