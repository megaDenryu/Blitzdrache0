import type { 升目の宣言, 壁の外面の飾り } from '../../../生成/編集資源契約.ts'
import { 側面のはめ口を読む, type 升目の側面 } from './升目の側面.ts'
import { 面に沿う箱の寸法, 面の中心を求める } from './升目の原点.ts'
import { ベイの奥行メートル, ベイの横幅メートル, 出窓の高さメートル, 表示する板の厚みメートル, 煙突の1段の高さメートル, 階の高さメートル, 飾りの出メートル, 飾りの幅メートル } from './ベイの寸法.ts'
import { 箱の立体を作る } from './立体の姿を組む.ts'
import type { 三次元の寸法, 表示する立体 } from './建物の立体の見取り.ts'

// 升目の1つの面が出す立体を数え上げる工程。壁の板と、その外面へ付く飾りを担当する。
// 飾りを段数のぶんだけ積むのは、平面図で選んだ段数が三次元の姿へそのまま出ないと、
// 人が段数を決める入力になっていないためである(エディター制作スキル第1条)。

export function 面の立体を数え上げる(宣言: 升目の宣言, 側面: 升目の側面, 原点: 三次元の寸法): 表示する立体[] {
    const 値 = 側面のはめ口を読む(宣言, 側面)
    if (値.種類 !== '壁を入れる') return []
    const 壁 = 箱の立体を作る('壁', 宣言.座標, 面の中心を求める(原点, 側面, 0), 壁の板の寸法(側面))
    return [壁, ...外面の飾りの立体を数え上げる(宣言, 側面, 原点, 値.値.外面の飾り)]
}

function 壁の板の寸法(側面: 升目の側面): 三次元の寸法 {
    return 面に沿う箱の寸法(側面, 面に沿う辺の長さ(側面), 表示する板の厚みメートル, 階の高さメートル)
}

// 正面と背面は横幅の辺に沿い、左面と右面は奥行の辺に沿う。
function 面に沿う辺の長さ(側面: 升目の側面): number {
    return 側面 === '正面' || 側面 === '背面' ? ベイの横幅メートル : ベイの奥行メートル
}

function 外面の飾りの立体を数え上げる(
    宣言: 升目の宣言,
    側面: 升目の側面,
    原点: 三次元の寸法,
    飾り: 壁の外面の飾り,
): 表示する立体[] {
    if (飾り.種類 === '付けない') return []
    const 中心 = 面の中心を求める(原点, 側面, 飾りの出メートル / 2)
    if (飾り.種類 === '出窓を差し込む') {
        const 寸法 = 面に沿う箱の寸法(側面, 飾りの幅メートル, 飾りの出メートル, 出窓の高さメートル)
        return [箱の立体を作る('飾り', 宣言.座標, 中心, 寸法)]
    }
    return 煙突の立体を数え上げる(宣言, 側面, 中心, 飾り.値.段数)
}

// 煙突は壁の中ほどから上へ積む。3段で屋根を越えて伸びる姿になる。
function 煙突の立体を数え上げる(
    宣言: 升目の宣言,
    側面: 升目の側面,
    面の中心: 三次元の寸法,
    段数: number,
): 表示する立体[] {
    const 寸法 = 面に沿う箱の寸法(側面, 飾りの出メートル, 飾りの出メートル, 煙突の1段の高さメートル)
    return Array.from({ length: 段数 }, (_値, 添字) =>
        箱の立体を作る(
            '飾り',
            宣言.座標,
            { x: 面の中心.x, y: 面の中心.y + 添字 * 煙突の1段の高さメートル, z: 面の中心.z },
            寸法,
        ),
    )
}
