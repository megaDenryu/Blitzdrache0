import type { 建物の入口方向, 升目の座標 } from '../../../生成/編集資源契約.ts'
import { 入口方向が向く側面を読む } from './入口の向く面.ts'
import { 升目の原点を求める, 面に沿う箱の寸法, 面の中心を求める } from './升目の原点.ts'
import { 入口の印の厚みメートル, 入口の印の奥行メートル, 入口の印の幅メートル } from './ベイの寸法.ts'
import { 箱の立体を作る } from './立体の姿を組む.ts'
import type { 表示する立体 } from './建物の立体の見取り.ts'

// 根の升目のどの面が入口かを、地面へ敷いた踏み石として三次元へ出す工程。
// 入口の向きを選んでも三次元の姿が1つも変わらないと、人は選べたかどうかを画面から読めない
// (エディター制作スキル第5条: 押しても画面が変わらない操作を残さない)。

export function 入口の印の立体を数え上げる(根の升目: 升目の座標, 方向: 建物の入口方向): 表示する立体[] {
    const 側面 = 入口方向が向く側面を読む(方向)
    if (側面 === undefined) return []
    const 原点 = 升目の原点を求める(根の升目)
    const 中心 = 面の中心を求める(原点, 側面, 入口の印の奥行メートル / 2)
    return [
        箱の立体を作る(
            '入口の印',
            根の升目,
            { x: 中心.x, y: 原点.y + 入口の印の厚みメートル / 2, z: 中心.z },
            面に沿う箱の寸法(側面, 入口の印の幅メートル, 入口の印の奥行メートル, 入口の印の厚みメートル),
        ),
    ]
}
