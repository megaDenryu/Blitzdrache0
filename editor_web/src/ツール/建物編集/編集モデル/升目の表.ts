import type { はめ口の値, 升目の宣言, 升目の屋根, 升目の座標, 升目の床, 壁の外面の飾り } from '../../../生成/編集資源契約.ts'
import { 升目の座標を比べる, 升目の鍵を作る } from './升目の鍵.ts'
import { 外面の飾りを差し替えた宣言, 側面のはめ口を差し替えた宣言, 全側面, type 升目の側面 } from './升目の側面.ts'
import { 四面へ壁を入れた升目 } from './初期の建物の格子を作る.ts'
import { 升目を置けない理由を在り処から調べる, 面へ壁を入れられない理由を在り処から調べる, type 升目を消せない理由 } from './格子の成り立ちの判定.ts'
import { 消した後の格子 } from './消した後の格子.ts'
import { 屋根を外した宣言, 屋根を戻した宣言, 継がれる面の壁を外した宣言, 継がれる面へ壁を戻した宣言, 継ぐ面の壁を外した宣言, 真下の座標, 真上の座標, 隣の座標 } from './隣接の整合をとる.ts'

// 座標から升目の宣言を引く表。升目の置き消しと、その結果として隣と真下の升目に要る継ぎ目の整えをこの型が持ち、
// 置けない座標と消せない升目を自分で拒む。整えと拒みを呼び出し側へ散らすと、サーバーが拒む格子を編集の途中で
// 作れてしまう。根は格子ぜんたいの性質であるため、消す側の口が引数で受ける。
export class 升目の表 {
    private readonly _座標ごとの宣言 = new Map<string, 升目の宣言>()

    public 宣言を1件預ける(宣言: 升目の宣言): void {
        this._座標ごとの宣言.set(升目の鍵を作る(宣言.座標), 宣言)
    }

    public 宣言を引く(座標: 升目の座標): 升目の宣言 | undefined {
        return this._座標ごとの宣言.get(升目の鍵を作る(座標))
    }

    public 升目があるか(座標: 升目の座標): boolean {
        return this._座標ごとの宣言.has(升目の鍵を作る(座標))
    }

    public 升目が1つでもあるか(): boolean {
        return this._座標ごとの宣言.size > 0
    }

    public 昇順に並べる(): 升目の宣言[] {
        return Array.from(this._座標ごとの宣言.values()).sort((左, 右) => 升目の座標を比べる(左.座標, 右.座標))
    }

    // 升目を1つ置き、隣と真下の升目との継ぎ目を整える。置けない座標では何もしない。
    public 升目を置く(座標: 升目の座標): void {
        if (升目を置けない理由を在り処から調べる(this, 座標) !== undefined) return
        this.宣言を1件預ける(継ぐ面の壁を外した宣言(四面へ壁を入れた升目(座標), (側面) => this.升目があるか(隣の座標(座標, 側面))))
        for (const 側面 of 全側面) {
            const 隣の宣言 = this.宣言を引く(隣の座標(座標, 側面))
            if (隣の宣言 !== undefined) this.宣言を1件預ける(継がれる面の壁を外した宣言(隣の宣言, 側面))
        }
        const 真下の宣言 = this.宣言を引く(真下の座標(座標))
        if (真下の宣言 !== undefined) this.宣言を1件預ける(屋根を外した宣言(真下の宣言))
    }

    public 消した後の格子を見通す(いまの根: 升目の座標, 消す座標: 升目の座標): 消した後の格子 {
        return 消した後の格子.消す升目を名指して求める(this.昇順に並べる(), いまの根, 消す座標)
    }

    // 消すと浮く升目や根から到達できない升目が生じるなら拒む。連鎖して他の升目を消すことはしない。
    public 升目を消せない理由を調べる(座標: 升目の座標, いまの根: 升目の座標): 升目を消せない理由 | undefined {
        if (!this.升目があるか(座標)) return undefined
        return this.消した後の格子を見通す(いまの根, 座標).成り立たない理由()
    }

    // 升目を1つ消し、隣の面の壁と真下の屋根を戻す。置いたときに外した継ぎ目を元へ戻す向きの整えである。
    public 升目を消す(座標: 升目の座標, いまの根: 升目の座標): boolean {
        if (this.升目を消せない理由を調べる(座標, いまの根) !== undefined) return false
        if (!this._座標ごとの宣言.delete(升目の鍵を作る(座標))) return false
        for (const 側面 of 全側面) {
            const 隣の宣言 = this.宣言を引く(隣の座標(座標, 側面))
            if (隣の宣言 !== undefined) this.宣言を1件預ける(継がれる面へ壁を戻した宣言(隣の宣言, 側面))
        }
        const 真下の宣言 = this.宣言を引く(真下の座標(座標))
        if (真下の宣言 !== undefined) this.宣言を1件預ける(屋根を戻した宣言(真下の宣言))
        return true
    }

    // 継ぎ口へ壁を入れる要求は黙って捨てる。判定の正本は`面へ壁を入れられない理由を調べる`の1つである。
    public 側面の値を定める(座標: 升目の座標, 側面: 升目の側面, 値: はめ口の値): void {
        const 宣言 = this.宣言を引く(座標)
        if (宣言 === undefined) return
        if (値.種類 === '壁を入れる' && 面へ壁を入れられない理由を在り処から調べる(this, 座標, 側面) !== undefined) return
        this.宣言を1件預ける(側面のはめ口を差し替えた宣言(宣言, 側面, 値))
    }

    // 壁の外面の飾りを付け替える。壁の入っていない面への要求は黙って捨てる。
    public 面の飾りを定める(座標: 升目の座標, 側面: 升目の側面, 飾り: 壁の外面の飾り): void {
        const 宣言 = this.宣言を引く(座標)
        if (宣言 === undefined) return
        const 差し替えた = 外面の飾りを差し替えた宣言(宣言, 側面, 飾り)
        if (差し替えた !== undefined) this.宣言を1件預ける(差し替えた)
    }

    public 床を定める(座標: 升目の座標, 床: 升目の床): void {
        const 宣言 = this.宣言を引く(座標)
        if (宣言 !== undefined) this.宣言を1件預ける({ ...宣言, 床 })
    }

    // 屋根が載るのは真上に升目の無い升目だけである。載せられない要求は黙って捨てる。
    public 屋根を定める(座標: 升目の座標, 屋根: 升目の屋根): void {
        const 宣言 = this.宣言を引く(座標)
        if (宣言 === undefined || (屋根 === '載せる' && this.升目があるか(真上の座標(座標)))) return
        this.宣言を1件預ける({ ...宣言, 屋根 })
    }
}
