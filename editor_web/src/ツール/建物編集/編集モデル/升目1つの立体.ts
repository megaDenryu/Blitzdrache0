import type { 升目の宣言 } from '../../../生成/編集資源契約.ts'
import { 全側面 } from './升目の側面.ts'
import { 升目の原点を求める } from './升目の原点.ts'
import { ベイの奥行メートル, ベイの横幅メートル, 表示する薄板の厚みメートル } from './ベイの寸法.ts'
import { 箱の立体を作る } from './立体の姿を組む.ts'
import { 切妻の屋根を数え上げる } from './屋根の立体.ts'
import { 面の立体を数え上げる } from './面の立体.ts'
import { 骨組みの立体を数え上げる } from './骨組みの立体.ts'
import type { 三次元の寸法, 表示する立体 } from './建物の立体の見取り.ts'

// 升目1つが三次元表示へ出す立体の数え上げ。骨組みを必ず出し、床と屋根と4面を宣言のとおりに足す。
// 部分ごとの形の決め方はそれぞれのファイルが持ち、ここはどれをいくつ出すかだけを決める。

export function 升目1つの立体を数え上げる(宣言: 升目の宣言): 表示する立体[] {
    const 原点 = 升目の原点を求める(宣言.座標)
    return [
        ...骨組みの立体を数え上げる(宣言.座標, 原点),
        ...(宣言.床 === '張る' ? [床の板を作る(宣言, 原点)] : []),
        ...(宣言.屋根 === '載せる' ? 切妻の屋根を数え上げる(宣言.座標, 原点) : []),
        ...全側面.flatMap((側面) => 面の立体を数え上げる(宣言, 側面, 原点)),
    ]
}

function 床の板を作る(宣言: 升目の宣言, 原点: 三次元の寸法): 表示する立体 {
    return 箱の立体を作る(
        '床',
        宣言.座標,
        { x: 原点.x, y: 原点.y + 表示する薄板の厚みメートル / 2, z: 原点.z },
        { x: ベイの横幅メートル, y: 表示する薄板の厚みメートル, z: ベイの奥行メートル },
    )
}
