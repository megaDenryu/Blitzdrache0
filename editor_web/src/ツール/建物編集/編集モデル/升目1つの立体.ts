import type { 升目の宣言, 升目の座標 } from '../../../生成/編集資源契約.ts'
import { 側面のはめ口を読む, 全側面, 側面へ進む増分, type 升目の側面 } from './升目の側面.ts'
import { ベイの奥行メートル, ベイの横幅メートル, 表示する小箱の一辺メートル, 表示する板の厚みメートル, 表示する薄板の厚みメートル, 階の高さメートル } from './ベイの寸法.ts'
import type { 三次元の寸法, 表示する立体 } from './建物の立体の見取り.ts'

// 升目1つが三次元の識別色表示へ出す立体の数え上げ。骨格の線の枠を必ず1つ出し、
// 床と屋根と壁と飾りを宣言のとおりに足す。屋根は2枚の勾配の板で簡略な切妻を表す。

const 屋根の勾配ラジアン = Math.PI / 7

export function 升目1つの立体を数え上げる(宣言: 升目の宣言): 表示する立体[] {
    const 原点 = 升目の原点を求める(宣言.座標)
    const 立体一覧: 表示する立体[] = [
        箱を作る('骨格', { x: 原点.x, y: 原点.y + 階の高さメートル / 2, z: 原点.z }, {
            x: ベイの横幅メートル,
            y: 階の高さメートル,
            z: ベイの奥行メートル,
        }),
    ]
    if (宣言.床 === '張る') {
        立体一覧.push(
            箱を作る('床', { x: 原点.x, y: 原点.y + 表示する薄板の厚みメートル / 2, z: 原点.z }, {
                x: ベイの横幅メートル,
                y: 表示する薄板の厚みメートル,
                z: ベイの奥行メートル,
            }),
        )
    }
    if (宣言.屋根 === '載せる') 立体一覧.push(...切妻の2枚を作る(原点))
    for (const 側面 of 全側面) 立体一覧.push(...その面の立体を数え上げる(宣言, 側面, 原点))
    return 立体一覧
}

// 升目の床の中心。横はローカルのxが増える向きへ、奥はローカルのzが減る向きへ並ぶ。
function 升目の原点を求める(座標: 升目の座標): 三次元の寸法 {
    return {
        x: 座標.横 * ベイの横幅メートル,
        y: 座標.階 * 階の高さメートル,
        z: -座標.奥 * ベイの奥行メートル,
    }
}

function その面の立体を数え上げる(宣言: 升目の宣言, 側面: 升目の側面, 原点: 三次元の寸法): 表示する立体[] {
    const 値 = 側面のはめ口を読む(宣言, 側面)
    if (値.種類 !== '壁を入れる') return []
    const 壁の中心 = 面の中心を求める(原点, 側面, 0)
    const 立体一覧 = [箱を作る('壁', 壁の中心, 板の大きさを求める(側面))]
    if (値.値.外面の飾り.種類 === '付けない') return 立体一覧
    const 飾りの中心 = 面の中心を求める(原点, 側面, 表示する小箱の一辺メートル / 2)
    const 一辺 = 表示する小箱の一辺メートル
    立体一覧.push(箱を作る('飾り', 飾りの中心, { x: 一辺, y: 一辺, z: 一辺 }))
    return 立体一覧
}

// 名指した面の中心。外へ張り出す量を足すと、面より外側(飾りの位置)へ出る。
function 面の中心を求める(原点: 三次元の寸法, 側面: 升目の側面, 外への張り出しメートル: number): 三次元の寸法 {
    const 増分 = 側面へ進む増分(側面)
    const 半幅 = ベイの横幅メートル / 2 + 外への張り出しメートル
    const 半奥行 = ベイの奥行メートル / 2 + 外への張り出しメートル
    return {
        x: 原点.x + 増分.横 * 半幅,
        y: 原点.y + 階の高さメートル / 2,
        z: 原点.z - 増分.奥 * 半奥行,
    }
}

function 板の大きさを求める(側面: 升目の側面): 三次元の寸法 {
    const 増分 = 側面へ進む増分(側面)
    return {
        x: 増分.横 === 0 ? ベイの横幅メートル : 表示する板の厚みメートル,
        y: 階の高さメートル,
        z: 増分.奥 === 0 ? ベイの奥行メートル : 表示する板の厚みメートル,
    }
}

// 簡略な切妻。棟を横方向へ通し、奥行の前後へ勾配の板を1枚ずつ傾けて置く。
function 切妻の2枚を作る(原点: 三次元の寸法): 表示する立体[] {
    const 半奥行 = ベイの奥行メートル / 2
    const 勾配の長さ = 半奥行 / Math.cos(屋根の勾配ラジアン)
    const 棟の高さ = 原点.y + 階の高さメートル + (半奥行 * Math.tan(屋根の勾配ラジアン)) / 2
    return [1, -1].map((向き) => ({
        役割: '屋根' as const,
        中心メートル: { x: 原点.x, y: 棟の高さ, z: 原点.z + (向き * 半奥行) / 2 },
        大きさメートル: { x: ベイの横幅メートル, y: 表示する板の厚みメートル, z: 勾配の長さ },
        x軸まわりの傾きラジアン: -向き * 屋根の勾配ラジアン,
    }))
}

function 箱を作る(役割: 表示する立体['役割'], 中心メートル: 三次元の寸法, 大きさメートル: 三次元の寸法): 表示する立体 {
    return { 役割, 中心メートル, 大きさメートル, x軸まわりの傾きラジアン: 0 }
}
