import type { 建物の格子, 升目の宣言, 升目の座標 } from '../../../生成/編集資源契約.ts'
import { 建物の格子の形式版 } from '../../../生成/編集資源契約.ts'
import { 建物の名乗り } from './建物の名乗り.ts'

// 契約の値と編集の途中の状態のあいだの往復。編集モデルから分けるのは、触る材料が違うためである。
// ここは直列化の欄の並びと形式版だけを見て、升目の置き消しの規則を1つも知らない。

export function 契約の値から名乗りを読む(格子: 建物の格子): 建物の名乗り {
    return new 建物の名乗り(格子.建物定義ID, 格子.表示名, 格子.入口のローカル方向)
}

export function 契約の格子を組み立てる(
    名乗り: 建物の名乗り,
    根の升目: 升目の座標,
    升目一覧: 升目の宣言[],
): 建物の格子 {
    return {
        形式版: 建物の格子の形式版,
        建物定義ID: 名乗り.建物定義ID,
        表示名: 名乗り.表示名,
        入口のローカル方向: 名乗り.入口のローカル方向,
        格子: { 根の升目, 升目一覧 },
        装飾: {},
    }
}
