import type { 升目の宣言, 升目の座標 } from '../../../生成/編集資源契約.ts'
import { 升目の座標が同じか } from './升目の鍵.ts'
import { 残った升目が成り立たない理由, type 升目を消せない理由 } from './格子の成り立ちの判定.ts'

// 名指した升目を1つ消したときに残る格子の見通し。残る升目の座標と、そのときの根を持つ。
// 升目の表から分けるのは、ここが読み取りだけで決まり、表の書き換えを1つも起こさないためである。
// 根の付け替えと消せるかの判定を1つの型が答えるのは、どちらも「残る座標の一覧」という同じ材料から
// 決まり、別々に求めると根の付け替えと判定が食い違う組み合わせを作れてしまうためである。
export class 消した後の格子 {
    private constructor(
        private readonly _残った座標一覧: 升目の座標[],
        public readonly 根: 升目の座標,
    ) {}

    public static 消す升目を名指して求める(
        宣言一覧: readonly 升目の宣言[],
        いまの根: 升目の座標,
        消す座標: 升目の座標,
    ): 消した後の格子 {
        const 残った座標一覧 = 宣言一覧.map((宣言) => 宣言.座標).filter((座標) => !升目の座標が同じか(座標, 消す座標))
        return new 消した後の格子(残った座標一覧, 消した後の根を選ぶ(残った座標一覧, いまの根, 消す座標))
    }

    public 成り立たない理由(): 升目を消せない理由 | undefined {
        return 残った升目が成り立たない理由(this._残った座標一覧, this.根)
    }
}

// 根そのものを消すときだけ、残った升目のうち最も小さい座標へ根を移す。
function 消した後の根を選ぶ(残った座標一覧: 升目の座標[], いまの根: 升目の座標, 消す座標: 升目の座標): 升目の座標 {
    if (!升目の座標が同じか(いまの根, 消す座標) || 残った座標一覧.length === 0) return いまの根
    return 残った座標一覧[0]
}
