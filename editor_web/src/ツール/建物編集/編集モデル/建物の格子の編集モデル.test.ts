import { deepStrictEqual, strictEqual } from 'node:assert/strict'
import { describe, it } from 'node:test'
import { 建物の格子の編集モデル } from './建物の格子の編集モデル.ts'
import { 初期の建物の格子を作る } from './初期の建物の格子を作る.ts'
import { 側面のはめ口を読む } from './升目の側面.ts'

// 道具が作る初期の格子と、升目を置いたあとの継ぎ目の整えを確かめる。継ぎ目の整えは
// サーバーの保存の検査が拒む形(隣を継ぐ面へ壁を入れる・真上に升目がある升目へ屋根を載せる)を
// 編集の途中で作れなくするためにあり、破れると保存のたびに拒まれる。
describe('建物の格子の編集モデル', () => {
    it('初期の格子は1升目で4面すべてに壁が入る', () => {
        const モデル = 建物の格子の編集モデル.契約の値から復元する(初期の建物の格子を作る('grid_building_1', '新しい建物'))
        const 升目一覧 = モデル.升目を昇順に並べる()
        strictEqual(升目一覧.length, 1)
        strictEqual(升目一覧[0].正面.種類, '壁を入れる')
        strictEqual(升目一覧[0].屋根, '載せる')
        deepStrictEqual(モデル.根の升目, { 横: 0, 奥: 0, 階: 0 })
    })

    it('右隣へ升目を置くと両側の継ぎ口の壁が外れる', () => {
        const モデル = 建物の格子の編集モデル.契約の値から復元する(初期の建物の格子を作る('grid_building_1', '新しい建物'))
        モデル.升目を置く({ 横: 1, 奥: 0, 階: 0 })
        const 元の升目 = モデル.宣言を引く({ 横: 0, 奥: 0, 階: 0 })
        const 隣の升目 = モデル.宣言を引く({ 横: 1, 奥: 0, 階: 0 })
        strictEqual(元の升目 === undefined, false)
        strictEqual(隣の升目 === undefined, false)
        if (元の升目 === undefined || 隣の升目 === undefined) return
        strictEqual(側面のはめ口を読む(元の升目, '右面').種類, '入れない')
        strictEqual(側面のはめ口を読む(隣の升目, '左面').種類, '入れない')
    })

    it('真上へ升目を積むと下の升目の屋根が外れ、上の升目へは屋根が載る', () => {
        const モデル = 建物の格子の編集モデル.契約の値から復元する(初期の建物の格子を作る('grid_building_1', '新しい建物'))
        モデル.升目を置く({ 横: 0, 奥: 0, 階: 1 })
        strictEqual(モデル.宣言を引く({ 横: 0, 奥: 0, 階: 0 })?.屋根, '載せない')
        strictEqual(モデル.宣言を引く({ 横: 0, 奥: 0, 階: 1 })?.屋根, '載せる')
    })

    it('真上に升目がある升目へは屋根を載せ直せない', () => {
        const モデル = 建物の格子の編集モデル.契約の値から復元する(初期の建物の格子を作る('grid_building_1', '新しい建物'))
        モデル.升目を置く({ 横: 0, 奥: 0, 階: 1 })
        モデル.屋根を定める({ 横: 0, 奥: 0, 階: 0 }, '載せる')
        strictEqual(モデル.宣言を引く({ 横: 0, 奥: 0, 階: 0 })?.屋根, '載せない')
    })

    it('根の升目を消すと残った升目のうち最も小さい座標が根になる', () => {
        const モデル = 建物の格子の編集モデル.契約の値から復元する(初期の建物の格子を作る('grid_building_1', '新しい建物'))
        モデル.升目を置く({ 横: 1, 奥: 0, 階: 0 })
        モデル.升目を消す({ 横: 0, 奥: 0, 階: 0 })
        deepStrictEqual(モデル.根の升目, { 横: 1, 奥: 0, 階: 0 })
    })

    it('契約の値へ写して復元すると同じ格子になる', () => {
        const モデル = 建物の格子の編集モデル.契約の値から復元する(初期の建物の格子を作る('grid_building_1', '新しい建物'))
        モデル.升目を置く({ 横: 1, 奥: 0, 階: 0 })
        const 写し = モデル.契約の値へ写す()
        deepStrictEqual(建物の格子の編集モデル.契約の値から復元する(写し).契約の値へ写す(), 写し)
    })
})
