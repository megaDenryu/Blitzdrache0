import type { 建物の入口方向 } from '../../../生成/編集資源契約.ts'
import { 全側面, type 升目の側面 } from './升目の側面.ts'

// 入口がどの面を向くかを、升目の側面の語彙で表す。方向を裸の{x, z}のまま画面に出さないのは、
// 人が選ぶのは面であって数の組ではないためであり、斜めや零の向きを選べてしまう形にしないためである。
//
// 部品ローカルの軸との対応は骨格の側面の宣言が決めている。横は右面の法線の向き(ローカルのxが増える向き)、
// 奥は背面の法線の向き(ローカルのzが減る向き)である。よって正面は{x:0, z:1}であり、
// 新しい建物の既定の入口方向と、初期の升目が扉枠付きの壁を入れる面が同じ正面で一致する。
// 参照: `crates/blitz_assembly/src/building_grid/cell_coordinate.rs`

export function 側面から入口方向へ写す(側面: 升目の側面): 建物の入口方向 {
    switch (側面) {
        case '正面':
            return { x: 0, z: 1 }
        case '背面':
            return { x: 0, z: -1 }
        case '左面':
            return { x: -1, z: 0 }
        case '右面':
            return { x: 1, z: 0 }
    }
}

// 入口方向がどの面を向いているか。4方位のどれとも一致しない向きを持つ保存物では「無し」を返す。
export function 入口方向が向く側面を読む(方向: 建物の入口方向): 升目の側面 | undefined {
    return 全側面.find((側面) => {
        const 候補 = 側面から入口方向へ写す(側面)
        return 候補.x === 方向.x && 候補.z === 方向.z
    })
}
