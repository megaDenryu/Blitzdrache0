import type { はめ口の値, 建物の格子, 建物の入口方向, 升目の宣言, 升目の屋根, 升目の座標, 升目の床 } from '../../../生成/編集資源契約.ts'
import { 建物の格子の形式版 } from '../../../生成/編集資源契約.ts'
import type { 升目の側面 } from './升目の側面.ts'
import { 升目の表 } from './升目の表.ts'
import { 升目を置けない理由を在り処から調べる, 面へ壁を入れられない理由を在り処から調べる, type 升目を消せない理由, type 升目を置けない理由, type 面へ壁を入れられない理由 } from './格子の成り立ちの判定.ts'

// 建物1件の編集の状態。升目の表と、建物の名乗り(識別子・表示名・根の升目・入口の方向)を持つ。
// 契約の値との往復だけが直列化に触れ、編集の途中の状態はこの型の中に閉じる。
// 置ける・消せるの判定を口として出すのは、拒んだ理由をそのまま画面へ出すためである。
// 入口の方向は初期値のまま往復させるだけであり、選ぶ口は入口方向を選ぶUIを作るときに足す。
export class 建物の格子の編集モデル {
    private readonly _升目の表 = new 升目の表()

    private constructor(
        public readonly 建物定義ID: string,
        private _表示名: string,
        private _根の升目: 升目の座標,
        private _入口のローカル方向: 建物の入口方向,
    ) {}

    public static 契約の値から復元する(格子: 建物の格子): 建物の格子の編集モデル {
        const モデル = new 建物の格子の編集モデル(格子.建物定義ID, 格子.表示名, 格子.格子.根の升目, 格子.入口のローカル方向)
        for (const 宣言 of 格子.格子.升目一覧) {
            モデル._升目の表.宣言を1件預ける(宣言)
        }
        return モデル
    }

    public 契約の値へ写す(): 建物の格子 {
        return {
            形式版: 建物の格子の形式版,
            建物定義ID: this.建物定義ID,
            表示名: this._表示名,
            入口のローカル方向: this._入口のローカル方向,
            格子: { 根の升目: this._根の升目, 升目一覧: this._升目の表.昇順に並べる() },
            装飾: {},
        }
    }

    public 升目を昇順に並べる(): 升目の宣言[] {
        return this._升目の表.昇順に並べる()
    }

    public 宣言を引く(座標: 升目の座標): 升目の宣言 | undefined {
        return this._升目の表.宣言を引く(座標)
    }

    public 升目があるか(座標: 升目の座標): boolean {
        return this._升目の表.升目があるか(座標)
    }

    public 表示名を定める(表示名: string): void {
        this._表示名 = 表示名
    }

    public get 根の升目(): 升目の座標 {
        return this._根の升目
    }

    // 根にできるのは格子にある升目だけである。無い升目を指すと、保存の検査が必ず拒む格子になる。
    public 根を定める(座標: 升目の座標): void {
        if (this.升目があるか(座標)) this._根の升目 = 座標
    }

    public 升目を置けない理由を調べる(座標: 升目の座標): 升目を置けない理由 | undefined {
        return 升目を置けない理由を在り処から調べる(this, 座標)
    }

    public 升目を置く(座標: 升目の座標): void {
        this._升目の表.升目を置く(座標)
    }

    public 升目を消せない理由を調べる(座標: 升目の座標): 升目を消せない理由 | undefined {
        return this._升目の表.升目を消せない理由を調べる(座標, this._升目の表.消した後の根(this._根の升目, 座標))
    }

    // 根の升目を消したときは、残った升目のうち最も小さい座標を根にする。根が格子の外を指したままにしない。
    public 升目を消す(座標: 升目の座標): void {
        const 新しい根 = this._升目の表.消した後の根(this._根の升目, 座標)
        if (this._升目の表.升目を消す(座標, 新しい根)) this._根の升目 = 新しい根
    }

    public 面へ壁を入れられない理由を調べる(座標: 升目の座標, 側面: 升目の側面): 面へ壁を入れられない理由 | undefined {
        return 面へ壁を入れられない理由を在り処から調べる(this, 座標, 側面)
    }

    public 側面の値を定める(座標: 升目の座標, 側面: 升目の側面, 値: はめ口の値): void {
        this._升目の表.側面の値を定める(座標, 側面, 値)
    }

    public 床を定める(座標: 升目の座標, 床: 升目の床): void {
        this._升目の表.床を定める(座標, 床)
    }

    public 屋根を定める(座標: 升目の座標, 屋根: 升目の屋根): void {
        this._升目の表.屋根を定める(座標, 屋根)
    }
}
