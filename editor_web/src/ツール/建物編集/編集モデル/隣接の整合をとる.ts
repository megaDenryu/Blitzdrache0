import type { 升目の宣言, 升目の座標 } from '../../../生成/編集資源契約.ts'
import { 側面のはめ口を差し替えた宣言, 全側面, 向かい合う側面, 側面へ進む増分, type 升目の側面 } from './升目の側面.ts'
import { 壁を入れない, 壁を入れる } from './初期の建物の格子を作る.ts'

// 隣を継ぐ面へ壁を入れた格子と、真上に升目を積んだ升目へ屋根を載せた格子はサーバーが拒む。
// 人が升目を置いた時点で継ぐ面の壁と真下の屋根を外し、消した時点で外したぶんを戻す。
// 外す側と戻す側を同じ場所に置くのは、片方だけを直すと編集の途中で辻褄の合わない格子ができるためである。

export function 隣の座標(座標: 升目の座標, 側面: 升目の側面): 升目の座標 {
    const 増分 = 側面へ進む増分(側面)
    return { 横: 座標.横 + 増分.横, 奥: 座標.奥 + 増分.奥, 階: 座標.階 }
}

export function 真下の座標(座標: 升目の座標): 升目の座標 {
    return { 横: 座標.横, 奥: 座標.奥, 階: 座標.階 - 1 }
}

export function 真上の座標(座標: 升目の座標): 升目の座標 {
    return { 横: 座標.横, 奥: 座標.奥, 階: 座標.階 + 1 }
}

// 名指した升目のうち、隣の升目がある側面の壁を外した宣言。
export function 継ぐ面の壁を外した宣言(
    宣言: 升目の宣言,
    隣があるか: (側面: 升目の側面) => boolean,
): 升目の宣言 {
    return 全側面.reduce<升目の宣言>(
        (途中, 側面) => (隣があるか(側面) ? 側面のはめ口を差し替えた宣言(途中, 側面, 壁を入れない()) : 途中),
        宣言,
    )
}

// 名指した側面から継がれる側の升目の宣言。向かい合う面の壁を外す。
export function 継がれる面の壁を外した宣言(宣言: 升目の宣言, こちらの側面: 升目の側面): 升目の宣言 {
    return 側面のはめ口を差し替えた宣言(宣言, 向かい合う側面(こちらの側面), 壁を入れない())
}

// 隣の升目が消えて継ぎ口でなくなった面へ平壁を戻した宣言。外したときの壁の種類は覚えていないため、
// 建物の外周として無難な平壁で埋める(人が窓や扉へ塗り替えられる)。
export function 継がれる面へ壁を戻した宣言(宣言: 升目の宣言, こちらの側面: 升目の側面): 升目の宣言 {
    return 側面のはめ口を差し替えた宣言(宣言, 向かい合う側面(こちらの側面), 壁を入れる('平壁'))
}

export function 屋根を外した宣言(宣言: 升目の宣言): 升目の宣言 {
    return { ...宣言, 屋根: '載せない' }
}

// 真上の升目が消えて最上階になった升目へ屋根を戻した宣言。
export function 屋根を戻した宣言(宣言: 升目の宣言): 升目の宣言 {
    return { ...宣言, 屋根: '載せる' }
}
