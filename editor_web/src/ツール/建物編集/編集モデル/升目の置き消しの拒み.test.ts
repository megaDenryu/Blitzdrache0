import { deepStrictEqual, strictEqual } from 'node:assert/strict'
import { describe, it } from 'node:test'
import { 建物の格子の編集モデル } from './建物の格子の編集モデル.ts'
import { 初期の建物の格子を作る } from './初期の建物の格子を作る.ts'
import { 側面のはめ口を読む } from './升目の側面.ts'

// 道具が拒まれる格子を作れないことを確かめる。サーバーのベイ格子の検査が拒む形
// (真下に升目が無い・升目が1つも無い・根から到達できない・隣を継ぐ面へ壁)を、編集の途中で作れてはならない。
// 参照: `crates/blitz_assembly/src/building_grid/grid_validation.rs`・`spanning_tree.rs`
describe('升目の置き消しの拒み', () => {
    const 新しいモデル = (): 建物の格子の編集モデル =>
        建物の格子の編集モデル.契約の値から復元する(初期の建物の格子を作る('grid_building_1', '新しい建物'))

    it('真下に升目が無い座標へは升目を置けない', () => {
        const モデル = 新しいモデル()
        strictEqual(モデル.升目を置けない理由を調べる({ 横: 1, 奥: 0, 階: 1 }), '真下に升目が無いため階を積めない')
        モデル.升目を置く({ 横: 1, 奥: 0, 階: 1 })
        strictEqual(モデル.升目があるか({ 横: 1, 奥: 0, 階: 1 }), false)
    })

    it('真下に升目がある座標へは升目を置ける', () => {
        const モデル = 新しいモデル()
        strictEqual(モデル.升目を置けない理由を調べる({ 横: 0, 奥: 0, 階: 1 }), undefined)
        モデル.升目を置く({ 横: 0, 奥: 0, 階: 1 })
        strictEqual(モデル.升目があるか({ 横: 0, 奥: 0, 階: 1 }), true)
    })

    it('同じ階でも6つの近さに升目が無い離れた座標へは升目を置けない', () => {
        const モデル = 新しいモデル()
        strictEqual(
            モデル.升目を置けない理由を調べる({ 横: 2, 奥: 0, 階: 0 }),
            '隣にも真上にも真下にも升目が無いため格子から離れる',
        )
        モデル.升目を置く({ 横: 2, 奥: 0, 階: 0 })
        strictEqual(モデル.升目があるか({ 横: 2, 奥: 0, 階: 0 }), false)
    })

    it('隣に升目がある座標へは升目を置ける', () => {
        const モデル = 新しいモデル()
        strictEqual(モデル.升目を置けない理由を調べる({ 横: 1, 奥: 0, 階: 0 }), undefined)
        モデル.升目を置く({ 横: 1, 奥: 0, 階: 0 })
        strictEqual(モデル.升目を置けない理由を調べる({ 横: 2, 奥: 0, 階: 0 }), undefined)
    })

    it('消すと上の階が浮く升目は消せない', () => {
        const モデル = 新しいモデル()
        モデル.升目を置く({ 横: 0, 奥: 0, 階: 1 })
        strictEqual(モデル.升目を消せない理由を調べる({ 横: 0, 奥: 0, 階: 0 }), '真下が抜けて浮く升目ができる')
        モデル.升目を消す({ 横: 0, 奥: 0, 階: 0 })
        strictEqual(モデル.升目があるか({ 横: 0, 奥: 0, 階: 0 }), true)
    })

    it('消すと根から分断される升目ができる升目は消せない', () => {
        const モデル = 新しいモデル()
        モデル.升目を置く({ 横: 1, 奥: 0, 階: 0 })
        モデル.升目を置く({ 横: 2, 奥: 0, 階: 0 })
        strictEqual(モデル.升目を消せない理由を調べる({ 横: 1, 奥: 0, 階: 0 }), '根から到達できない升目ができる')
        モデル.升目を消す({ 横: 1, 奥: 0, 階: 0 })
        strictEqual(モデル.升目を昇順に並べる().length, 3)
    })

    it('格子の最後の升目は消せない', () => {
        const モデル = 新しいモデル()
        strictEqual(モデル.升目を消せない理由を調べる({ 横: 0, 奥: 0, 階: 0 }), '格子の最後の升目である')
        モデル.升目を消す({ 横: 0, 奥: 0, 階: 0 })
        strictEqual(モデル.升目を昇順に並べる().length, 1)
    })

    it('端の升目を消すと隣の面の壁と真下の屋根が戻る', () => {
        const モデル = 新しいモデル()
        モデル.升目を置く({ 横: 1, 奥: 0, 階: 0 })
        モデル.升目を置く({ 横: 0, 奥: 0, 階: 1 })
        モデル.升目を消す({ 横: 1, 奥: 0, 階: 0 })
        モデル.升目を消す({ 横: 0, 奥: 0, 階: 1 })
        const 残った升目 = モデル.宣言を引く({ 横: 0, 奥: 0, 階: 0 })
        strictEqual(残った升目 === undefined, false)
        if (残った升目 === undefined) return
        deepStrictEqual(側面のはめ口を読む(残った升目, '右面'), { 種類: '壁を入れる', 値: { 壁の種類: '平壁', 外面の飾り: { 種類: '付けない' } } })
        strictEqual(残った升目.屋根, '載せる')
    })

    it('隣を継ぐ面へは壁を入れられない', () => {
        const モデル = 新しいモデル()
        モデル.升目を置く({ 横: 1, 奥: 0, 階: 0 })
        strictEqual(モデル.面へ壁を入れられない理由を調べる({ 横: 0, 奥: 0, 階: 0 }, '右面'), '隣を継ぐ面には壁を入れられない')
        モデル.側面の値を定める({ 横: 0, 奥: 0, 階: 0 }, '右面', { 種類: '壁を入れる', 値: { 壁の種類: '平壁', 外面の飾り: { 種類: '付けない' } } })
        const 升目 = モデル.宣言を引く({ 横: 0, 奥: 0, 階: 0 })
        strictEqual(升目 === undefined, false)
        if (升目 === undefined) return
        strictEqual(側面のはめ口を読む(升目, '右面').種類, '入れない')
    })
})
