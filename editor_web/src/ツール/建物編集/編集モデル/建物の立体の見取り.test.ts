import { deepStrictEqual, ok, strictEqual } from 'node:assert/strict'
import { describe, it } from 'node:test'
import { 建物の格子の編集モデル } from './建物の格子の編集モデル.ts'
import { 初期の建物の格子を作る } from './初期の建物の格子を作る.ts'
import { 立体の見取りを組み立てる, 見取りの外接箱を求める, type 立体の役割, type 表示する立体 } from './建物の立体の見取り.ts'
import { ベイの奥行メートル, ベイの横幅メートル, 表示する板の厚みメートル, 階の高さメートル } from './ベイの寸法.ts'

// 升目1つが出す立体の顔ぶれと寸法を確かめる。寸法まで見るのは、この表示の役目が「形が見えること」だからである
// (判断13)。並びと場所は`建物の立体の場所.test.ts`が受け持つ。

const 新しいモデル = (): 建物の格子の編集モデル =>
    建物の格子の編集モデル.契約の値から復元する(初期の建物の格子を作る('grid_building_1', '新しい建物'))

const 役割で絞る = (見取り: readonly 表示する立体[], 役割: 立体の役割): 表示する立体[] =>
    見取り.filter((立体) => 立体.役割 === 役割)

describe('建物の立体の見取りが出す立体の顔ぶれと寸法', () => {
    it('升目1つが骨組み8本と床と屋根2枚と壁4枚と入口の印を出す', () => {
        const 見取り = 立体の見取りを組み立てる(新しいモデル())
        strictEqual(役割で絞る(見取り, '骨格').length, 8)
        strictEqual(役割で絞る(見取り, '床').length, 1)
        strictEqual(役割で絞る(見取り, '屋根').length, 2)
        strictEqual(役割で絞る(見取り, '壁').length, 4)
        strictEqual(役割で絞る(見取り, '飾り').length, 0)
        strictEqual(役割で絞る(見取り, '入口の印').length, 1)
    })

    it('壁の板が面ごとにベイの辺の長さと階の高さと板の厚みを持つ', () => {
        const 壁一覧 = 役割で絞る(立体の見取りを組み立てる(新しいモデル()), '壁')
        const 正面の壁 = 壁一覧.find((立体) => 立体.中心メートル.z > 0)
        const 右面の壁 = 壁一覧.find((立体) => 立体.中心メートル.x > 0)
        ok(正面の壁 !== undefined && 右面の壁 !== undefined)
        deepStrictEqual(正面の壁.姿.大きさメートル, {
            x: ベイの横幅メートル,
            y: 階の高さメートル,
            z: 表示する板の厚みメートル,
        })
        deepStrictEqual(右面の壁.姿.大きさメートル, {
            x: 表示する板の厚みメートル,
            y: 階の高さメートル,
            z: ベイの奥行メートル,
        })
    })

    it('屋根の2枚だけが傾いた板の姿を持つ', () => {
        const 傾いた板 = 立体の見取りを組み立てる(新しいモデル()).filter((立体) => 立体.姿.種類 === '傾いた板')
        strictEqual(傾いた板.length, 2)
        ok(傾いた板.every((立体) => 立体.役割 === '屋根'))
    })

    it('升目が1つも無い格子でも1ベイぶんの外接箱が決まる', () => {
        const 外接箱 = 見取りの外接箱を求める([])
        deepStrictEqual(外接箱.中心メートル, { x: 0, y: 階の高さメートル / 2, z: 0 })
        ok(外接箱.対角の長さメートル > ベイの奥行メートル)
    })
})
