import type { 升目の座標 } from '../../../生成/編集資源契約.ts'
import { 升目の鍵を作る } from './升目の鍵.ts'
import { 全側面, type 升目の側面 } from './升目の側面.ts'
import { 真下の座標, 真上の座標, 隣の座標 } from './隣接の整合をとる.ts'

// 升目を置けない事情・消せない事情・面へ壁を入れられない事情の語彙と、その判定。綴りはそのまま画面へ出す文言であり、
// サーバーのベイ格子の検査が拒む形(升目が1つも無い・真下に升目が無い・隣を継ぐ面へ壁・根から到達できない)と対応する。
// 参照: `crates/blitz_assembly/src/building_grid/grid_validation.rs`・`spanning_tree.rs`

export type 升目を置けない理由 =
    | 'すでに升目がある'
    | '真下に升目が無いため階を積めない'
    | '隣にも真上にも真下にも升目が無いため格子から離れる'

export type 升目を消せない理由 = '格子の最後の升目である' | '真下が抜けて浮く升目ができる' | '根から到達できない升目ができる'

export type 面へ壁を入れられない理由 = '隣を継ぐ面には壁を入れられない'

// 升目がその座標にあるかと、格子が空かだけを答える読み取りの口。置ける・壁を入れられるの判定は
// 近さと空かどうかしか見ないため、升目の表そのものを渡さずこの口だけで足りる。
export interface I升目の在り処 {
    升目があるか(座標: 升目の座標): boolean
    升目が1つでもあるか(): boolean
}

// 升目を置けるのは、まだ升目が無く、最も下の階か真下に升目があり、かつ格子が空でなければ6つの近さの
// いずれかに升目がある座標だけである。離れた座標へ置いた格子はサーバーが「根から到達できない」で拒むため、
// 置く時点で塞ぐ。空の格子には近さの相手が無いため、最初の1升目だけは近さを課さない。
export function 升目を置けない理由を在り処から調べる(在り処: I升目の在り処, 座標: 升目の座標): 升目を置けない理由 | undefined {
    if (在り処.升目があるか(座標)) return 'すでに升目がある'
    if (座標.階 > 0 && !在り処.升目があるか(真下の座標(座標))) return '真下に升目が無いため階を積めない'
    if (在り処.升目が1つでもあるか() && !継ぐ先の座標一覧(座標).some((隣) => 在り処.升目があるか(隣))) {
        return '隣にも真上にも真下にも升目が無いため格子から離れる'
    }
    return undefined
}

// 隣に升目がある面は継ぎ口であり、そこへ壁を入れた格子はサーバーが拒む。
export function 面へ壁を入れられない理由を在り処から調べる(
    在り処: I升目の在り処,
    座標: 升目の座標,
    側面: 升目の側面,
): 面へ壁を入れられない理由 | undefined {
    if (!在り処.升目があるか(座標)) return undefined
    return 在り処.升目があるか(隣の座標(座標, 側面)) ? '隣を継ぐ面には壁を入れられない' : undefined
}

// 名指した並びの升目だけが残ったときに保存の検査を通らなくなる事情。通るなら「無し」を返す。
export function 残った升目が成り立たない理由(
    残った座標一覧: readonly 升目の座標[],
    根: 升目の座標,
): 升目を消せない理由 | undefined {
    if (残った座標一覧.length === 0) return '格子の最後の升目である'
    const 残った鍵 = new Set(残った座標一覧.map(升目の鍵を作る))
    for (const 座標 of 残った座標一覧) {
        if (座標.階 > 0 && !残った鍵.has(升目の鍵を作る(真下の座標(座標)))) return '真下が抜けて浮く升目ができる'
    }
    return 根から張れた升目の数(残った鍵, 根) === 残った座標一覧.length ? undefined : '根から到達できない升目ができる'
}

// 根から幅優先で継ぎ先を辿り、張れた升目の数を返す。根が残りの中に無いときは1つも張れない。
function 根から張れた升目の数(残った鍵: ReadonlySet<string>, 根: 升目の座標): number {
    if (!残った鍵.has(升目の鍵を作る(根))) return 0
    const 張った鍵 = new Set<string>([升目の鍵を作る(根)])
    const 待ち行列: 升目の座標[] = [根]
    for (let 走査位置 = 0; 走査位置 < 待ち行列.length; 走査位置 += 1) {
        for (const 子 of 継ぐ先の座標一覧(待ち行列[走査位置])) {
            const 鍵 = 升目の鍵を作る(子)
            if (!残った鍵.has(鍵) || 張った鍵.has(鍵)) continue
            張った鍵.add(鍵)
            待ち行列.push(子)
        }
    }
    return 張った鍵.size
}

// 名指した升目から継ぎ先になる6つの座標。横の4面と真上と真下であり、サーバーが木を張るときの継ぎ方と同じ範囲である。
function 継ぐ先の座標一覧(座標: 升目の座標): 升目の座標[] {
    return [...全側面.map((側面) => 隣の座標(座標, 側面)), 真上の座標(座標), 真下の座標(座標)]
}
