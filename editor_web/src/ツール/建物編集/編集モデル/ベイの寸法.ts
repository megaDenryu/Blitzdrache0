// ベイ1つぶんの寸法。この道具の中で升目の刻みを綴る唯一の場所である。
//
// 値の正本は部品カタログの骨格が宣言する接合点であり、この綴りはその写しである。骨格の左右の継ぎ口は
// ローカルのx=±1.00にあるため横も奥も2.00メートル刻みで並び、骨格の上面はローカルの高さ2.60にあるため
// 階は2.60メートル刻みで積む。ブラウザは実部品のglbを配信しない(判断9)ため接合点から導けず、写しを持つ。
// 写しが2つになると片方だけを直した食い違いが絵の中でしか見えないため、綴りをこのファイルの外へ書かない。
// 参照: `crates/blitz_assembly/src/expansion/frame_tests/frame_chain_tests.rs`
// 参照: `_doc/設計/部品カタログと接合点.md`「骨格の上下積層とベイの継ぎ口(2026-08-19 追加)」

