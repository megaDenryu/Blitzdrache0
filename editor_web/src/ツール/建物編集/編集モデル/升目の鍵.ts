import type { 升目の座標 } from '../../../生成/編集資源契約.ts'

// 升目の座標から、Mapの鍵に使える綴りを作る純粋関数。JSのMapは参照等価のため、
// 座標の値オブジェクトをそのまま鍵にすると同じ升目を二重に置ける。
// 生値へ剥がすのは、鍵を持つ側の境界1箇所に閉じる。
export function 升目の鍵を作る(座標: 升目の座標): string {
    return `${座標.横}_${座標.奥}_${座標.階}`
}

// 座標を辞書式(横・奥・階の順)で比べる。同じ格子から常に同じ並びを得るために要る。
export function 升目の座標を比べる(左: 升目の座標, 右: 升目の座標): number {
    if (左.横 !== 右.横) return 左.横 - 右.横
    if (左.奥 !== 右.奥) return 左.奥 - 右.奥
    return 左.階 - 右.階
}

export function 升目の座標が同じか(左: 升目の座標, 右: 升目の座標): boolean {
    return 升目の座標を比べる(左, 右) === 0
}
