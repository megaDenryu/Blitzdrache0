import { 建物の格子の形式版, type はめ口の値, type 建物の格子, type 升目の宣言, type 升目の座標, type 壁の種類 } from '../../../生成/編集資源契約.ts'

// 道具が新しい建物を1件作った直後の格子。1升目に骨格を1件据え、4面すべてへ壁を入れ、床を張り屋根を載せる。
// この形は3箇所に同じ形を手書きしている(ここ・サーバー側の受入の検査の材料・HTTPの往復の材料)。言語と境界が
// 違うため綴りを1つに束ねられず、一致は目視と、サーバー側の試験(同じ形が保存の検査を通ること)で保つ。
// 参照: `crates/blitz_asset_compiler/src/building_grid_source/source_fixture.rs`
export function 初期の建物の格子を作る(建物定義ID: string, 表示名: string): 建物の格子 {
    return {
        形式版: 建物の格子の形式版,
        建物定義ID,
        表示名,
        入口のローカル方向: { x: 0, z: 1 },
        格子: {
            根の升目: 原点の座標(),
            升目一覧: [四面へ壁を入れた升目(原点の座標())],
        },
        装飾: {},
    }
}

export function 原点の座標(): 升目の座標 {
    return { 横: 0, 奥: 0, 階: 0 }
}

export function 壁を入れる(種類: 壁の種類): はめ口の値 {
    return { 種類: '壁を入れる', 値: { 壁の種類: 種類, 外面の飾り: { 種類: '付けない' } } }
}

export function 壁を入れない(): はめ口の値 {
    return { 種類: '入れない' }
}

// 人が升目を1つ置いた直後の姿。正面に扉枠付きの壁、左面に窓壁、残る2面に平壁を入れる。
export function 四面へ壁を入れた升目(座標: 升目の座標): 升目の宣言 {
    return {
        座標,
        正面: 壁を入れる('扉枠付きの壁'),
        背面: 壁を入れる('平壁'),
        左面: 壁を入れる('窓壁'),
        右面: 壁を入れる('平壁'),
        床: '張る',
        屋根: '載せる',
    }
}
