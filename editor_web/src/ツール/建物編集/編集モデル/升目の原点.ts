import type { 升目の座標 } from '../../../生成/編集資源契約.ts'
import { 側面へ進む増分, type 升目の側面 } from './升目の側面.ts'
import { ベイの奥行メートル, ベイの横幅メートル, 階の高さメートル } from './ベイの寸法.ts'
import type { 三次元の寸法 } from './建物の立体の見取り.ts'

// 升目の座標を三次元のメートルへ写す計算。座標から場所への写しをこの1つに閉じるのは、
// 簡易の形を組む側(骨組み・壁・屋根・飾り・入口の印)がどれも同じ写しを要るためである。

// 升目の床の中心。横はローカルのxが増える向きへ、奥はローカルのzが減る向きへ並ぶ。
export function 升目の原点を求める(座標: 升目の座標): 三次元の寸法 {
    return {
        x: 座標.横 * ベイの横幅メートル,
        y: 座標.階 * 階の高さメートル,
        z: -座標.奥 * ベイの奥行メートル,
    }
}

// 名指した面の中心。外への張り出しを足すと、面より外側(飾りや入口の印の位置)へ出る。
export function 面の中心を求める(原点: 三次元の寸法, 側面: 升目の側面, 外への張り出しメートル: number): 三次元の寸法 {
    const 増分 = 側面へ進む増分(側面)
    const 半幅 = ベイの横幅メートル / 2 + 外への張り出しメートル
    const 半奥行 = ベイの奥行メートル / 2 + 外への張り出しメートル
    return {
        x: 原点.x + 増分.横 * 半幅,
        y: 原点.y + 階の高さメートル / 2,
        z: 原点.z - 増分.奥 * 半奥行,
    }
}

// 面に沿う向き・面から外へ出る向き・縦の3つの寸法を、その面での直方体の寸法へ並べ替える。
// 面ごとにどの軸が「沿う」で どの軸が「外へ」かが入れ替わるため、並べ替えをこの1つに閉じる。
export function 面に沿う箱の寸法(
    側面: 升目の側面,
    面に沿う幅メートル: number,
    外へ出る深さメートル: number,
    縦の高さメートル: number,
): 三次元の寸法 {
    const 増分 = 側面へ進む増分(側面)
    return 増分.横 === 0
        ? { x: 面に沿う幅メートル, y: 縦の高さメートル, z: 外へ出る深さメートル }
        : { x: 外へ出る深さメートル, y: 縦の高さメートル, z: 面に沿う幅メートル }
}
