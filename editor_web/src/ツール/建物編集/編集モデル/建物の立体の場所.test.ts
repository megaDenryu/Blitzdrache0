import { ok, strictEqual } from 'node:assert/strict'
import { describe, it } from 'node:test'
import { 建物の格子の編集モデル } from './建物の格子の編集モデル.ts'
import { 初期の建物の格子を作る } from './初期の建物の格子を作る.ts'
import { 立体の見取りを組み立てる, type 立体の役割, type 表示する立体 } from './建物の立体の見取り.ts'
import { ベイの奥行メートル, ベイの横幅メートル, 煙突の1段の高さメートル, 階の高さメートル } from './ベイの寸法.ts'

// 立体がどこへ並ぶかを確かめる。升目の座標と入口の向きと飾りの段数が、そのまま三次元の場所と数へ出ることが、
// この表示を人の判断の入力として使える条件である(エディター制作スキル第1条)。

const 新しいモデル = (): 建物の格子の編集モデル =>
    建物の格子の編集モデル.契約の値から復元する(初期の建物の格子を作る('grid_building_1', '新しい建物'))

const 役割で絞る = (見取り: readonly 表示する立体[], 役割: 立体の役割): 表示する立体[] =>
    見取り.filter((立体) => 立体.役割 === 役割)

describe('建物の立体が並ぶ場所', () => {
    it('隣へ升目を置くと骨組みがベイの横幅だけ離れて並ぶ', () => {
        const モデル = 新しいモデル()
        モデル.升目を置く({ 横: 1, 奥: 0, 階: 0 })
        const 横の値 = 役割で絞る(立体の見取りを組み立てる(モデル), '骨格').map((立体) => 立体.中心メートル.x)
        strictEqual(横の値.length, 16)
        strictEqual(Math.max(...横の値) - Math.min(...横の値), ベイの横幅メートル * 2)
    })

    it('階を積むと骨組みが階の高さだけ上へ載る', () => {
        const モデル = 新しいモデル()
        モデル.升目を置く({ 横: 0, 奥: 0, 階: 1 })
        const 骨格一覧 = 役割で絞る(立体の見取りを組み立てる(モデル), '骨格')
        const 階ごとの最も低い骨格 = (階: number): number =>
            Math.min(...骨格一覧.filter((立体) => 立体.属する升目の座標.階 === 階).map((立体) => 立体.中心メートル.y))
        ok(Math.abs(階ごとの最も低い骨格(1) - 階ごとの最も低い骨格(0) - 階の高さメートル) < 1e-9)
    })

    it('立体は自分が属する升目の座標を持ち、その升目の場所へ据わる', () => {
        const モデル = 新しいモデル()
        モデル.升目を置く({ 横: 1, 奥: 0, 階: 0 })
        const 隣の升目の立体 = 立体の見取りを組み立てる(モデル).filter((立体) => 立体.属する升目の座標.横 === 1)
        ok(隣の升目の立体.length > 0)
        ok(隣の升目の立体.every((立体) => 立体.中心メートル.x > 0))
    })

    it('煙突は選んだ段数のぶんだけ上へ積む', () => {
        const モデル = 新しいモデル()
        モデル.面の飾りを定める({ 横: 0, 奥: 0, 階: 0 }, '正面', { 種類: '煙突を立てる', 値: { 段数: 3 } })
        const 高さ一覧 = 役割で絞る(立体の見取りを組み立てる(モデル), '飾り')
            .map((立体) => 立体.中心メートル.y)
            .sort((左, 右) => 左 - 右)
        strictEqual(高さ一覧.length, 3)
        ok(Math.abs(高さ一覧[1] - 高さ一覧[0] - 煙突の1段の高さメートル) < 1e-9)
    })

    it('出窓は面の外側へ1つだけ張り出す', () => {
        const モデル = 新しいモデル()
        モデル.面の飾りを定める({ 横: 0, 奥: 0, 階: 0 }, '正面', { 種類: '出窓を差し込む' })
        const 飾り一覧 = 役割で絞る(立体の見取りを組み立てる(モデル), '飾り')
        strictEqual(飾り一覧.length, 1)
        ok(飾り一覧[0].中心メートル.z > ベイの奥行メートル / 2)
    })

    it('入口の向きを変えると入口の印がその面の外へ移る', () => {
        const モデル = 新しいモデル()
        const 正面のとき = 役割で絞る(立体の見取りを組み立てる(モデル), '入口の印')[0]
        ok(正面のとき.中心メートル.z > 0 && Math.abs(正面のとき.中心メートル.x) < 1e-9)
        モデル.名乗り.入口の方向を定める({ x: 1, z: 0 })
        const 右面のとき = 役割で絞る(立体の見取りを組み立てる(モデル), '入口の印')[0]
        ok(右面のとき.中心メートル.x > 0 && Math.abs(右面のとき.中心メートル.z) < 1e-9)
    })
})
