import type { 升目の座標 } from '../../../生成/編集資源契約.ts'
import { ベイの奥行メートル, ベイの横幅メートル, 表示する板の厚みメートル, 階の高さメートル } from './ベイの寸法.ts'
import { 傾いた板の立体を作る } from './立体の姿を組む.ts'
import type { 三次元の寸法, 表示する立体 } from './建物の立体の見取り.ts'

// 升目1つに載る切妻の屋根を数え上げる工程。棟を横方向へ通し、奥行の前後へ勾配の板を1枚ずつ傾けて置く。
// 屋根だけが傾いた板の姿を使うため、傾きの計算をこの1つのファイルへ閉じる。

const 屋根の勾配ラジアン = Math.PI / 7

export function 切妻の屋根を数え上げる(座標: 升目の座標, 原点: 三次元の寸法): 表示する立体[] {
    const 半奥行 = ベイの奥行メートル / 2
    const 勾配の長さ = 半奥行 / Math.cos(屋根の勾配ラジアン)
    const 棟の高さ = 原点.y + 階の高さメートル + (半奥行 * Math.tan(屋根の勾配ラジアン)) / 2
    return [1, -1].map((向き) =>
        傾いた板の立体を作る(
            '屋根',
            座標,
            { x: 原点.x, y: 棟の高さ, z: 原点.z + (向き * 半奥行) / 2 },
            { x: ベイの横幅メートル, y: 表示する板の厚みメートル, z: 勾配の長さ },
            -向き * 屋根の勾配ラジアン,
        ),
    )
}
