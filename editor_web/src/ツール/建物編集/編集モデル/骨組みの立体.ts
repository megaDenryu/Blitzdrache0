import type { 升目の座標 } from '../../../生成/編集資源契約.ts'
import { ベイの奥行メートル, ベイの横幅メートル, 梁の高さメートル, 柱の一辺メートル, 階の高さメートル } from './ベイの寸法.ts'
import { 箱の立体を作る } from './立体の姿を組む.ts'
import type { 三次元の寸法, 表示する立体 } from './建物の立体の見取り.ts'

// 升目1つの骨組みを、四隅の柱と柱の頭をつなぐ梁として数え上げる工程。
// 線の枠の箱ではなく実際の角材の並びで出すのは、判断13が「形そのものを編集する対象は形が見える表示にする」を
// 定めているためである。壁を外した升目でも、木造の骨組みとして寸法と組み方が読める。
// 参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断13」

const 半幅メートル = ベイの横幅メートル / 2

const 半奥行メートル = ベイの奥行メートル / 2

export function 骨組みの立体を数え上げる(座標: 升目の座標, 原点: 三次元の寸法): 表示する立体[] {
    return [...四隅の柱を数え上げる(座標, 原点), ...頭をつなぐ梁を数え上げる(座標, 原点)]
}

function 四隅の柱を数え上げる(座標: 升目の座標, 原点: 三次元の寸法): 表示する立体[] {
    const 太さ = { x: 柱の一辺メートル, y: 階の高さメートル, z: 柱の一辺メートル }
    const 柱の中心の高さ = 原点.y + 階の高さメートル / 2
    return 四隅の向き().map(({ 横向き, 奥向き }) =>
        箱の立体を作る(
            '骨格',
            座標,
            { x: 原点.x + 横向き * 半幅メートル, y: 柱の中心の高さ, z: 原点.z + 奥向き * 半奥行メートル },
            太さ,
        ),
    )
}

function 頭をつなぐ梁を数え上げる(座標: 升目の座標, 原点: 三次元の寸法): 表示する立体[] {
    const 梁の中心の高さ = 原点.y + 階の高さメートル - 梁の高さメートル / 2
    const 横へ渡す = { x: ベイの横幅メートル + 柱の一辺メートル, y: 梁の高さメートル, z: 柱の一辺メートル }
    const 奥へ渡す = { x: 柱の一辺メートル, y: 梁の高さメートル, z: ベイの奥行メートル + 柱の一辺メートル }
    return [
        ...[1, -1].map((奥向き) =>
            箱の立体を作る('骨格', 座標, { x: 原点.x, y: 梁の中心の高さ, z: 原点.z + 奥向き * 半奥行メートル }, 横へ渡す),
        ),
        ...[1, -1].map((横向き) =>
            箱の立体を作る('骨格', 座標, { x: 原点.x + 横向き * 半幅メートル, y: 梁の中心の高さ, z: 原点.z }, 奥へ渡す),
        ),
    ]
}

function 四隅の向き(): { 横向き: number; 奥向き: number }[] {
    return [
        { 横向き: 1, 奥向き: 1 },
        { 横向き: 1, 奥向き: -1 },
        { 横向き: -1, 奥向き: 1 },
        { 横向き: -1, 奥向き: -1 },
    ]
}
