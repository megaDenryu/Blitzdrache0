import type { チャンク編集画面部品 } from './画面/index.ts'
import type { チャンク編集状態 } from './チャンク編集状態.ts'
import type { チャンク編集操作サービス } from './チャンク編集操作サービス.ts'

// 下パネルの棚(これから使う筆と置くもの)の出来事を、UI状態と操作サービスへつなぐ。
//
// 道具の種類を選んだときにモードも移すのは、棚がどのモードでも見えているためである。
// モードを移さないと、材質を選んだのに左ドラッグが造成のままになり、押した結果が画面に返らない
// (エディター制作スキル第5条)。半径や流量のつまみでモードを移さないのは、それが
// 「どの道具を使うか」の選択ではなく、選んである道具の目盛りだからである。
export function 棚の出来事を配線する(
    部品: チャンク編集画面部品,
    状態: チャンク編集状態,
    操作: チャンク編集操作サービス,
): void {
    const 棚 = 部品.棚.部品
    棚.地形の筆.配線する({
        on筆致種別変更: (種別) => {
            状態.造成筆致種別 = 種別
            操作.モードを移す('造成')
        },
        on半径変更: (半径) => { 状態.造成半径 = 半径 },
        on強さ変更: (強さ) => { 状態.造成強さ = 強さ },
    })
    棚.地表の材質.配線する({
        on材質層変更: (層) => {
            状態.材質層 = 層
            操作.モードを移す('地表ペイント')
        },
        on半径変更: (半径) => { 状態.ペイント半径 = 半径 },
        on流量変更: (流量) => { 状態.ペイント流量 = 流量 },
    })
    棚.置ける建物.配線する({
        on建物を置く: (建物定義ID) => {
            操作.建物生成(建物定義ID)
            操作.モードを移す('建物')
        },
    })
}
