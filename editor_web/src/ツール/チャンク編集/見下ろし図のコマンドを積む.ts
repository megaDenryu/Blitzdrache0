import type { 編集コマンド } from '../../生成/編集資源契約.ts'
import type { チャンク編集画面部品 } from './画面/index.ts'
import type { チャンク編集操作サービス } from './チャンク編集操作サービス.ts'

export type コマンドを積む関数 = (コマンド: 編集コマンド) => void

// 見下ろし図の操作とパネルが積むコマンドの入口。生成が拒まれたときは例外の理由の文が飛ぶため、ここで捕まえて
// 操作帯の下の帯へ出す(設計正本の操作契約)。通ったときは前の理由を消し、古い文言が残らないようにする。
export function 例外を帯へ出してコマンドを積む(部品: チャンク編集画面部品, 操作: チャンク編集操作サービス): コマンドを積む関数 {
    return (コマンド) => {
        try {
            操作.コマンドを実行する(コマンド)
            部品.お知らせ.消す()
        } catch (例外) {
            部品.お知らせ.文言を出す(例外 instanceof Error ? 例外.message : String(例外))
        }
    }
}
