import type { 下書きと正本の揃い, 見下ろし図の下書きの管理 } from './編集モデル/index.ts'
import type { チャンク編集画面部品 } from './画面/index.ts'
import type { チャンク編集状態 } from './チャンク編集状態.ts'

// 同期が読むチャンクのうち、見下ろし図のパネルに要る2つ。
export interface 下書きを持つチャンク {
    readonly 下書き: 見下ろし図の下書きの管理
    readonly 下書きと正本の揃い: 下書きと正本の揃い
}

// 右サイドバーの等高線パネルと大升パネルを編集モデルの下書きへ合わせる。コマンドの適用と取り消しで等高線が減り、
// 選んでいた添字が範囲の外へ出ることがあるため、選択の後始末もここで行う。
export function 見下ろし図のパネルを同期する(部品: チャンク編集画面部品, UI状態: チャンク編集状態, チャンク: 下書きを持つチャンク): void {
    const 一覧 = チャンク.下書き.等高線一覧を取得する()
    const 見下ろし図 = UI状態.見下ろし図
    if (見下ろし図.選択中の等高線の添字 !== null && 見下ろし図.選択中の等高線の添字 >= 一覧.length) {
        見下ろし図.選択中の等高線の添字 = null
    }
    const 選んだ線 = 見下ろし図.選択中の等高線の添字 === null ? undefined : 一覧[見下ろし図.選択中の等高線の添字]
    部品.インスペクター.部品.等高線.表示を更新する(選んだ線 === undefined ? null : 選んだ線.高さメートル, チャンク.下書きと正本の揃い)
    部品.インスペクター.部品.大升.表示を更新する(チャンク.下書きと正本の揃い)
}
