// 同期が読むチャンクのうち、見下ろし図のパネルに要るもの。
export interface 下書きを持つチャンク {
    readonly 下書き: 見下ろし図の下書きの管理
    readonly 下書きと正本の揃い: 下書きと正本の揃い
    選択中の粗マスの升内平均を求める(一辺の升目数: number, 列: number, 行: number): 粗マス1つの升内平均
}

// 右サイドバーの等高線パネルと粗マスパネルを編集モデルの下書きへ合わせる。コマンドの適用と取り消しで等高線が減り、
// 選んでいた添字が範囲の外へ出ることがあるため、選択の後始末もここで行う。粗マスの選択は、選んだときの一辺の
// 升目数がいまの下書きと違えば外す(一辺を変えると(列,行)の指す場所が変わるため。設計正本の判断4)。
export function 見下ろし図のパネルを同期する(部品: チャンク編集画面部品, UI状態: チャンク編集状態, チャンク: 下書きを持つチャンク): void {
    const 見下ろし図 = UI状態.見下ろし図
    const 等高線一覧 = チャンク.下書き.等高線一覧を取得する()
    if (見下ろし図.選択中の等高線の添字 !== null && 見下ろし図.選択中の等高線の添字 >= 等高線一覧.length) {
        見下ろし図.選択中の等高線の添字 = null
    }
    const 選んだ線 = 見下ろし図.選択中の等高線の添字 === null ? undefined : 等高線一覧[見下ろし図.選択中の等高線の添字]
    部品.インスペクター.部品.等高線.表示を更新する(選んだ線 === undefined ? null : 等高線情報を組む(選んだ線), チャンク.下書きと正本の揃い)

    const 一辺の升目数 = チャンク.下書き.粗マスの一辺の升目数を取得する()
    if (見下ろし図.選択中の粗マスの番地 !== null && 見下ろし図.選択中の粗マスを選んだ一辺の升目数 !== 一辺の升目数) {
        見下ろし図.選択中の粗マスの番地 = null
        見下ろし図.選択中の粗マスを選んだ一辺の升目数 = null
    }
    const 選んだ番地 = 見下ろし図.選択中の粗マスの番地
    部品.インスペクター.部品.粗マス.表示を更新する(
        選んだ番地 === null ? null : 粗マス情報を組む(チャンク, 一辺の升目数, 選んだ番地),
        チャンク.下書きと正本の揃い,
    )
}

function 等高線情報を組む(線: ReturnType<見下ろし図の下書きの管理['等高線一覧を取得する']>[number]): 選択中の等高線情報 {
    let 長さメートル = 0
    for (const [甲, 乙] of 線分の列を作る(線)) 長さメートル += 二点の距離(甲, 乙)
    return { 高さメートル: 線.高さメートル, 頂点数: 線.頂点列.length, 閉じているか: 線.閉じている, 長さメートル }
}

function 粗マス情報を組む(
    チャンク: 下書きを持つチャンク,
    一辺の升目数: number,
    番地: { readonly 列: number; readonly 行: number },
): 選択中の粗マス情報 {
    const 塗り = チャンク.下書き.粗マスの塗り一覧を取得する().find((塗り) => 塗り.列 === 番地.列 && 塗り.行 === 番地.行)
    const 平均 = チャンク.選択中の粗マスの升内平均を求める(一辺の升目数, 番地.列, 番地.行)
    return {
        列: 番地.列,
        行: 番地.行,
        塗った高さメートル: 塗り?.高さメートル ?? null,
        塗った層: 塗り?.層 ?? null,
        現在の平均高さメートル: 平均.高さ平均メートル,
        現在の重みが最大の層: 平均.重みが最大の層,
    }
}
