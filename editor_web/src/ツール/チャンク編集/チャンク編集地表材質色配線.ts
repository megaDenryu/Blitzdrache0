import type { プロジェクト保管庫接続 } from '../../境界/通信/index.ts'
import type { マテリアル台帳 } from '../../生成/編集資源契約.ts'
import { 既定の台帳を組み立てる } from '../マテリアル/編集モデル/index.ts'
import type { チャンク編集画面 } from './画面/index.ts'
import type { 地表材質色 } from './画面/三次元/地形/地表材質色.ts'

// チャンク編集の3Dビューと見下ろし図の地表4層の識別色を、マテリアル台帳(未保存なら既定の台帳)の
// 層割当→識別色から注入する。タブを開いた時点で1回だけ反映し、以降の同期はしない
// (参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断9」)。
export async function 地表材質色を注入する(画面: チャンク編集画面, 保管庫: プロジェクト保管庫接続): Promise<void> {
    const 結果 = await 保管庫.マテリアル台帳を読む()
    const 台帳 = 結果.種別 === '成功' ? 結果.値 : 既定の台帳を組み立てる()
    const 材質色 = 材質色を解決する(台帳)
    画面.部品.三次元ビュー.地形.地表材質色を更新する(材質色)
    画面.部品.見下ろし図.配色を設定する({ 材質色 })
}

function 材質色を解決する(台帳: マテリアル台帳): 地表材質色 {
    const 既定 = 既定の台帳を組み立てる()
    const 材質色表 = new Map(台帳.マテリアル一覧.map((定義) => [定義.エンジン材質名, 定義.識別色]))
    const 既定色表 = new Map(既定.マテリアル一覧.map((定義) => [定義.エンジン材質名, 定義.識別色]))
    const 引く = (層: keyof マテリアル台帳['層割当']): string =>
        材質色表.get(台帳.層割当[層]) ?? 既定色表.get(既定.層割当[層]) ?? '#888888'
    return { 草: 引く('草'), 泥: 引く('泥'), 岩: 引く('岩'), 砂: 引く('砂') }
}
