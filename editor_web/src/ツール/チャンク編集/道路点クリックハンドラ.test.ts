import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import {
    チャンク座標,
    ハンドラを組む,
    初期状態を作る,
    当たり一覧,
} from './道路点クリックハンドラ試験の下ごしらえ.ts'

describe('道路点クリックハンドラの分岐', () => {
    it('既存の道路点に当たると、その位置を先頭に共有した新しい道が始まりアクティブが移ること', () => {
        const モデル = 初期状態を作る()
        const { 選択状態, ハンドラ } = ハンドラを組む(モデル, { 道路添字: 0, 制御点添字: 1 })

        assert.strictEqual(ハンドラ.分岐を始める(当たり一覧), true, '分岐が始まること')

        const 道路一覧 = モデル.チャンクを取得する(チャンク座標).道路一覧
        assert.strictEqual(道路一覧.件数, 2, '道が1本増えること')
        assert.strictEqual(選択状態.アクティブな道路の添字, 1, 'アクティブが新しい道へ移ること')
        assert.deepStrictEqual(
            道路一覧.道路を取り出す(1).制御点列,
            [{ x: 10, y: 2, z: 0 }],
            '分かれ元の点と同じ位置を先頭に持つこと',
        )
        assert.strictEqual(道路一覧.道路を取り出す(1).全幅メートル, 7, '分かれ元の幅を受け継ぐこと')
        assert.strictEqual(道路一覧.道路を取り出す(1).散布除外バッファメートル, 13, '分かれ元の散布除外バッファを受け継ぐこと')
        assert.deepStrictEqual(
            道路一覧.道路を取り出す(0).制御点列,
            [{ x: -10, y: 1, z: 0 }, { x: 10, y: 2, z: 0 }],
            '分かれ元の道は変わらないこと',
        )
    })

    it('道路点に当たらなければ分岐しないこと', () => {
        const モデル = 初期状態を作る()
        const { 選択状態, ハンドラ } = ハンドラを組む(モデル, null)

        assert.strictEqual(ハンドラ.分岐を始める(当たり一覧), false, '分岐が始まらないこと')
        assert.strictEqual(モデル.チャンクを取得する(チャンク座標).道路一覧.件数, 1, '道の本数が変わらないこと')
        assert.strictEqual(選択状態.アクティブな道路の添字, 0, 'アクティブが変わらないこと')
    })

    it('アクティブな道が無いところで描き足すと、その点を先頭に持つ道が1本始まること', () => {
        const モデル = 初期状態を作る()
        const { 選択状態, ハンドラ } = ハンドラを組む(モデル, null)
        選択状態.アクティブな道路の添字 = null

        ハンドラ.描き足す({ x: 3, y: 4, z: 5 })

        const 道路一覧 = モデル.チャンクを取得する(チャンク座標).道路一覧
        assert.strictEqual(道路一覧.件数, 2, '道が1本増えること')
        assert.strictEqual(選択状態.アクティブな道路の添字, 1, 'アクティブが新しい道へ移ること')
        assert.deepStrictEqual(道路一覧.道路を取り出す(1).制御点列, [{ x: 3, y: 4, z: 5 }])
    })
})
