import type { 造成筆致, 材質の筆致 } from '../../../生成/編集資源契約.ts'
import type { ワールド編集状態 } from '../編集モデル/index.ts'
import type { 造成筆致差し戻し, 材質の筆致差し戻し } from './差し戻し断片.ts'

export function 造成筆致を適用する(状態: ワールド編集状態, 値: 造成筆致): 造成筆致差し戻し {
    if (状態.選択中チャンク座標 !== null) {
        const チャンク = 状態.チャンクを取得する(状態.選択中チャンク座標)
        const 変更前格子データ = new Float32Array(チャンク.高さ場.格子データ)
        チャンク.高さ場.造成筆致を適用する(値)
        return { 種類: '造成筆致', 対象チャンク: { ...状態.選択中チャンク座標 }, 変更前格子データ }
    }
    const 変更前格子データ = new Float32Array(状態.大域高さ場.格子データ)
    状態.大域高さ場.造成筆致を適用する(値)
    return { 種類: '造成筆致', 対象チャンク: null, 変更前格子データ }
}

export function 材質の筆致を適用する(状態: ワールド編集状態, 値: 材質の筆致): 材質の筆致差し戻し {
    if (状態.選択中チャンク座標 === null) {
        throw new Error('材質の筆致を適用するにはチャンクを選択する必要がある')
    }
    const チャンク = 状態.チャンクを取得する(状態.選択中チャンク座標)
    const 変更前材質データ = new Uint8Array(チャンク.地表材質.材質データ)
    チャンク.地表材質.材質筆致を適用する(値)
    return {
        種類: '材質の筆致',
        対象チャンク: { ...状態.選択中チャンク座標 },
        変更前材質データ,
    }
}
