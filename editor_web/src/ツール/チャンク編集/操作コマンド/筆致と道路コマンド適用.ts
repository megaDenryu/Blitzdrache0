import type {
    造成筆致,
    材質の筆致,
    道路点を追加する,
    道路点を挿入する,
    道路点を移動する,
    道路点を削除する,
    道路対象,
} from '../../../生成/編集資源契約.ts'
import type { ワールド編集状態, 道路スプライン } from '../編集モデル/index.ts'
import type {
    造成筆致差し戻し,
    材質の筆致差し戻し,
    道路点を追加する差し戻し,
    道路点を挿入する差し戻し,
    道路点を移動する差し戻し,
    道路点を削除する差し戻し,
} from './差し戻し断片.ts'

function 道路スプラインを取得する(状態: ワールド編集状態, 対象: 道路対象): 道路スプライン {
    if (対象.種類 === '広域') {
        return 状態.広域道路
    }
    return 状態.チャンクを取得する(対象.値).道路
}

export function 造成筆致を適用する(状態: ワールド編集状態, 値: 造成筆致): 造成筆致差し戻し {
    if (状態.選択中チャンク座標 !== null) {
        const チャンク = 状態.チャンクを取得する(状態.選択中チャンク座標)
        const 変更前格子データ = new Float32Array(チャンク.高さ場.格子データ)
        チャンク.高さ場.造成筆致を適用する(値)
        return { 種類: '造成筆致', 対象チャンク: { ...状態.選択中チャンク座標 }, 変更前格子データ }
    }
    const 変更前格子データ = new Float32Array(状態.大域高さ場.格子データ)
    状態.大域高さ場.造成筆致を適用する(値)
    return { 種類: '造成筆致', 対象チャンク: null, 変更前格子データ }
}

export function 材質の筆致を適用する(状態: ワールド編集状態, 値: 材質の筆致): 材質の筆致差し戻し {
    if (状態.選択中チャンク座標 === null) {
        throw new Error('材質の筆致を適用するにはチャンクを選択する必要がある')
    }
    const チャンク = 状態.チャンクを取得する(状態.選択中チャンク座標)
    const 変更前材質データ = new Uint8Array(チャンク.地表材質.材質データ)
    チャンク.地表材質.材質筆致を適用する(値)
    return {
        種類: '材質の筆致',
        対象チャンク: { ...状態.選択中チャンク座標 },
        変更前材質データ,
    }
}

export function 道路点を追加するコマンドを適用する(状態: ワールド編集状態, 値: 道路点を追加する): 道路点を追加する差し戻し {
    const 道路 = 道路スプラインを取得する(状態, 値.対象)
    道路.点を追加する(値.位置)
    return {
        種類: '道路点を追加する',
        対象: 値.対象,
        追加された添字: 道路.制御点列.length - 1,
    }
}

export function 道路点を挿入するコマンドを適用する(状態: ワールド編集状態, 値: 道路点を挿入する): 道路点を挿入する差し戻し {
    const 道路 = 道路スプラインを取得する(状態, 値.対象)
    道路.点を添字へ挿入する(値.添字, 値.位置)
    return {
        種類: '道路点を挿入する',
        対象: 値.対象,
        挿入された添字: 値.添字,
    }
}

export function 道路点を移動するコマンドを適用する(状態: ワールド編集状態, 値: 道路点を移動する): 道路点を移動する差し戻し {
    const 道路 = 道路スプラインを取得する(状態, 値.対象)
    const 元の点 = 道路.制御点列[値.添字]
    if (元の点 === undefined) {
        throw new Error(`移動対象の道路点添字が範囲外: 添字=${値.添字}`)
    }
    const 変更前位置 = { ...元の点 }
    道路.点を移動する(値.添字, 値.新しい位置)
    return {
        種類: '道路点を移動する',
        対象: 値.対象,
        添字: 値.添字,
        変更前位置,
    }
}

export function 道路点を削除するコマンドを適用する(状態: ワールド編集状態, 値: 道路点を削除する): 道路点を削除する差し戻し {
    const 道路 = 道路スプラインを取得する(状態, 値.対象)
    const 削除された位置 = 道路.点を削除する(値.添字)
    return {
        種類: '道路点を削除する',
        対象: 値.対象,
        添字: 値.添字,
        削除された位置,
    }
}
