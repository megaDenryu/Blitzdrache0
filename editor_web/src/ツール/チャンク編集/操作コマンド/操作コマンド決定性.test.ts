import { describe, it } from "node:test"
import assert from "node:assert/strict"
import { ワールド編集状態, 空の見下ろし図の下書き } from "../編集モデル/index.ts"
import { 編集コマンドを適用する } from "./index.ts"
import type { 編集コマンド, 大域世界構造, チャンク構造 } from "../../../生成/編集資源契約.ts"

function 初期状態を作成する(): ワールド編集状態 {
    const 大域構造: 大域世界構造 = {
        区画割り: { 一辺のメートル: 512, 軸あたりチャンク数: 2, チャンクあたり格子解像度: 33 },
        広域道路一覧: [{
            制御点列: [
                { x: -100, y: 0, z: 0 },
                { x: 100, y: 0, z: 0 },
            ],
            全幅メートル: 12,
            細分割数: 20,
        }],
    }
    const 状態 = new ワールド編集状態(大域構造)
    const チャンク構造00: チャンク構造 = {
        道路一覧: [{
            制御点列: [
                { x: -50, y: 5, z: -50 },
                { x: 50, y: 5, z: 50 },
            ],
            全幅メートル: 6,
            散布除外バッファメートル: 10,
            細分割数: 20,
        }],
        建物一覧: [],
        散布: { 最小間隔メートル: 5.0, 乱数の種: 12345n },
        散布の個体一覧: [],
        見下ろし図の下書き: 空の見下ろし図の下書き(),
    }
    状態.チャンクを登録する({ x: 0, z: 0 }, チャンク構造00)
    return 状態
}

describe("操作コマンド層の決定性", () => {
    it("同じコマンド列を同じ初期状態へ2回適用した結果がバイト一致すること", () => {
        const コマンド列: Array<編集コマンド> = [
            { 種類: "造成筆致", 値: { 種別: "盛る", 通過点列: [{ x: 5, y: 0, z: 5 }], 半径メートル: 20, 強さ: 4.0 } },
            { 種類: "材質の筆致", 値: { 層: "砂", 通過点列: [{ x: 5, y: 0, z: 5 }], 半径メートル: 15, 流量: 0.7 } },
            { 種類: "急勾配を岩肌へベイクする", 値: { チャンク座標: { x: 0, z: 0 } } },
        ]

        const 状態1 = 初期状態を作成する()
        状態1.選択中チャンク座標 = { x: 0, z: 0 }
        for (const cmd of コマンド列) 編集コマンドを適用する(状態1, cmd)

        const 状態2 = 初期状態を作成する()
        状態2.選択中チャンク座標 = { x: 0, z: 0 }
        for (const cmd of コマンド列) 編集コマンドを適用する(状態2, cmd)

        const チャンク1 = 状態1.チャンクを取得する({ x: 0, z: 0 })
        const チャンク2 = 状態2.チャンクを取得する({ x: 0, z: 0 })

        const 高さ1 = new Uint8Array(チャンク1.高さ場.格子データ.buffer)
        const 高さ2 = new Uint8Array(チャンク2.高さ場.格子データ.buffer)
        assert.deepStrictEqual(高さ1, 高さ2, "2回適用した結果の高さ場が完全バイト一致するべき")

        const 材質1 = new Uint8Array(チャンク1.地表材質.材質データ.buffer)
        const 材質2 = new Uint8Array(チャンク2.地表材質.材質データ.buffer)
        assert.deepStrictEqual(材質1, 材質2, "2回適用した結果の地表材質が完全バイト一致するべき")
    })
})
