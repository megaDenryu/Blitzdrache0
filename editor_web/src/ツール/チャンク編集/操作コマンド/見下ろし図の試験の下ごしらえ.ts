import type { 編集コマンド, 等高線, 大域世界構造, チャンク構造 } from '../../../生成/編集資源契約.ts'
import { ワールド編集状態, 空の見下ろし図の下書き } from '../編集モデル/index.ts'

// 見下ろし図コマンドの適用・差し戻し・決定性の試験が共有する、起伏のある高さ場を持つ1チャンクと8枝を全部通る
// コマンド列の組み立て。試験の下ごしらえだけに使い、製品の経路からは呼ばない。

export const 見下ろし図の試験のチャンク座標 = { x: 0, z: 0 }
const 解像度 = 33

export function 起伏のあるチャンクの編集状態を作る(): ワールド編集状態 {
    const 大域構造: 大域世界構造 = {
        区画割り: { 一辺のメートル: 512, 軸あたりチャンク数: 2, チャンクあたり格子解像度: 解像度 - 1 },
        広域道路一覧: [],
    }
    const 状態 = new ワールド編集状態(大域構造)
    const 構造: チャンク構造 = {
        道路一覧: [],
        建物一覧: [],
        散布: { 最小間隔メートル: 5.0, 乱数の種: 12345n },
        散布の個体一覧: [],
        見下ろし図の下書き: 空の見下ろし図の下書き(),
    }
    const 高さ = new Float32Array(解像度 * 解像度)
    for (let i = 0; i < 高さ.length; i++) 高さ[i] = Math.sin(i * 0.37) * 5 + 3
    状態.チャンクを登録する(見下ろし図の試験のチャンク座標, 構造, 高さ)
    状態.選択中チャンク座標 = 見下ろし図の試験のチャンク座標
    return 状態
}

export function 正方形の等高線(半辺: number, 高さ: number): 等高線 {
    return {
        高さメートル: 高さ,
        頂点列: [{ x: -半辺, z: -半辺 }, { x: 半辺, z: -半辺 }, { x: 半辺, z: 半辺 }, { x: -半辺, z: 半辺 }],
        閉じている: true,
    }
}

// 等高線の追加・変更・削除、大升の塗り、生成2枝、逆導出2枝の順に、8枝を全部通る。
export function 見下ろし図の8枝を通るコマンド列(): Array<編集コマンド> {
    const チャンク座標 = 見下ろし図の試験のチャンク座標
    return [
        { 種類: '等高線を追加する', 値: { チャンク座標, 等高線: 正方形の等高線(96, 4) } },
        { 種類: '等高線を追加する', 値: { チャンク座標, 等高線: 正方形の等高線(32, 12) } },
        { 種類: '等高線を変更する', 値: { チャンク座標, 添字: 1, 等高線: 正方形の等高線(40, 14) } },
        { 種類: '等高線を追加する', 値: { チャンク座標, 等高線: 正方形の等高線(64, 9) } },
        { 種類: '等高線を削除する', 値: { チャンク座標, 添字: 2 } },
        { 種類: '等高線から高さ場を生成する', 値: { チャンク座標 } },
        {
            種類: '大升を塗る',
            値: {
                チャンク座標,
                大升の一辺の升目数: 8,
                塗り一覧: [{ 列: 1, 行: 1, 高さメートル: 20, 層: '岩' }, { 列: 2, 行: 1, 高さメートル: null, 層: '砂' }],
            },
        },
        { 種類: '大升から地形を生成する', 値: { チャンク座標 } },
        { 種類: '高さ場から等高線を導く', 値: { チャンク座標, 間隔メートル: 2 } },
        { 種類: '高さ場から大升を導く', 値: { チャンク座標, 大升の一辺の升目数: 4 } },
    ]
}
