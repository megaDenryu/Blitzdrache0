import type { ワールド編集状態 } from '../編集モデル/index.ts'
import type { 差し戻し断片, 地形と建物の差し戻し断片 } from './差し戻し断片.ts'

// 高さ場・地表材質・建物・散布の側の差し戻し。差し戻しの適用の網羅switchは、この側の断片をまとめてここへ振り分ける。
// 高さ場か地表材質を戻す枝は、見下ろし図の下書きと正本の揃いも変更前へ戻す。

export function 地形と建物の差し戻し断片か(断片: 差し戻し断片): 断片 is 地形と建物の差し戻し断片 {
    switch (断片.種類) {
        case '造成筆致':
        case '材質の筆致':
        case '建物を配置する':
        case '建物を移動する':
        case '建物を削除する':
        case '散布設定を変更する':
        case '道路に合わせて切土盛土する':
        case '建物基礎を平坦化する':
        case '急勾配を岩肌へベイクする':
        case '道路下を泥へベイクする':
            return true
        default:
            return false
    }
}

export function 地形と建物の差し戻しを適用する(状態: ワールド編集状態, 断片: 地形と建物の差し戻し断片): void {
    switch (断片.種類) {
        case '造成筆致': {
            if (断片.対象チャンク === null) {
                状態.大域高さ場.格子データを置き換える(断片.変更前格子データ)
                return
            }
            const チャンク = 状態.チャンクを取得する(断片.対象チャンク)
            チャンク.高さ場.格子データを置き換える(断片.変更前格子データ)
            if (断片.変更前の揃い !== null) チャンク.下書きと正本の揃い = 断片.変更前の揃い
            return
        }
        case '材質の筆致': {
            const チャンク = 状態.チャンクを取得する(断片.対象チャンク)
            チャンク.地表材質.材質データを置き換える(断片.変更前材質データ)
            チャンク.下書きと正本の揃い = 断片.変更前の揃い
            return
        }
        case '建物を配置する': {
            状態.チャンクを取得する(断片.チャンク座標).建物.削除する(断片.建物識別子)
            return
        }
        case '建物を移動する': {
            状態.チャンクを取得する(断片.チャンク座標).建物.移動する(断片.識別子, 断片.変更前位置, 断片.変更前向きラジアン)
            return
        }
        case '建物を削除する': {
            状態.チャンクを取得する(断片.チャンク座標).建物.配置する(断片.削除された建物)
            return
        }
        case '散布設定を変更する': {
            状態.チャンクを取得する(断片.チャンク座標).散布 = { ...断片.変更前設定 }
            return
        }
        case '道路に合わせて切土盛土する':
        case '建物基礎を平坦化する': {
            const チャンク = 状態.チャンクを取得する(断片.チャンク座標)
            チャンク.高さ場.格子データを置き換える(断片.変更前格子データ)
            チャンク.下書きと正本の揃い = 断片.変更前の揃い
            return
        }
        case '急勾配を岩肌へベイクする': {
            const チャンク = 状態.チャンクを取得する(断片.チャンク座標)
            チャンク.地表材質.材質データを置き換える(断片.変更前材質データ)
            チャンク.下書きと正本の揃い = 断片.変更前の揃い
            return
        }
        case '道路下を泥へベイクする': {
            const チャンク = 状態.チャンクを取得する(断片.チャンク座標)
            チャンク.地表材質.材質データを置き換える(断片.変更前材質データ)
            チャンク.地表材質.道路の泥の被覆の記録を写しから戻す(断片.変更前の道路の泥の被覆の記録)
            チャンク.下書きと正本の揃い = 断片.変更前の揃い
            return
        }
    }
    const 網羅性検査: never = 断片
    throw new Error(`未対応の地形と建物の差し戻し断片種類: ${JSON.stringify(網羅性検査)}`)
}
