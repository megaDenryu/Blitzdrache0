import type { ワールド編集状態 } from '../編集モデル/index.ts'
import { 道路対象の道路スプラインを取り出す } from '../編集モデル/index.ts'
import type { 差し戻し断片 } from './差し戻し断片.ts'

// 差し戻し断片の情報に基づき、編集状態を変更前の値へ復元する。
export function 差し戻しを適用する(状態: ワールド編集状態, 断片: 差し戻し断片): void {
    switch (断片.種類) {
        case '造成筆致': {
            if (断片.対象チャンク !== null) {
                const チャンク = 状態.チャンクを取得する(断片.対象チャンク)
                チャンク.高さ場.格子データを置き換える(断片.変更前格子データ)
            } else {
                状態.大域高さ場.格子データを置き換える(断片.変更前格子データ)
            }
            return
        }
        case '材質の筆致': {
            const チャンク = 状態.チャンクを取得する(断片.対象チャンク)
            チャンク.地表材質.材質データを置き換える(断片.変更前材質データ)
            return
        }
        case '道路点を追加する': {
            const 道路 = 道路対象の道路スプラインを取り出す(状態, 断片.対象)
            道路.点を削除する(断片.追加された添字)
            return
        }
        case '道路点を挿入する': {
            const 道路 = 道路対象の道路スプラインを取り出す(状態, 断片.対象)
            道路.点を削除する(断片.挿入された添字)
            return
        }
        case '道路点を移動する': {
            const 道路 = 道路対象の道路スプラインを取り出す(状態, 断片.対象)
            道路.点を移動する(断片.添字, 断片.変更前位置)
            return
        }
        case '道路点を削除する': {
            const 道路 = 道路対象の道路スプラインを取り出す(状態, 断片.対象)
            道路.点を添字へ挿入する(断片.添字, 断片.削除された位置)
            return
        }
        case '建物を配置する': {
            const チャンク = 状態.チャンクを取得する(断片.チャンク座標)
            チャンク.建物.削除する(断片.建物識別子)
            return
        }
        case '建物を移動する': {
            const チャンク = 状態.チャンクを取得する(断片.チャンク座標)
            チャンク.建物.移動する(断片.識別子, 断片.変更前位置, 断片.変更前向きラジアン)
            return
        }
        case '建物を削除する': {
            const チャンク = 状態.チャンクを取得する(断片.チャンク座標)
            チャンク.建物.配置する(断片.削除された建物)
            return
        }
        case '散布設定を変更する': {
            const チャンク = 状態.チャンクを取得する(断片.チャンク座標)
            チャンク.散布 = { ...断片.変更前設定 }
            return
        }
        case '道路に合わせて切土盛土する': {
            const チャンク = 状態.チャンクを取得する(断片.チャンク座標)
            チャンク.高さ場.格子データを置き換える(断片.変更前格子データ)
            return
        }
        case '建物基礎を平坦化する': {
            const チャンク = 状態.チャンクを取得する(断片.チャンク座標)
            チャンク.高さ場.格子データを置き換える(断片.変更前格子データ)
            return
        }
        case '急勾配を岩肌へベイクする': {
            const チャンク = 状態.チャンクを取得する(断片.チャンク座標)
            チャンク.地表材質.材質データを置き換える(断片.変更前材質データ)
            return
        }
        case '道路下を泥へベイクする': {
            const チャンク = 状態.チャンクを取得する(断片.チャンク座標)
            チャンク.地表材質.材質データを置き換える(断片.変更前材質データ)
            return
        }
    }
    const 網羅性検査: never = 断片
    throw new Error(`未対応の差し戻し断片種類: ${JSON.stringify(網羅性検査)}`)
}
