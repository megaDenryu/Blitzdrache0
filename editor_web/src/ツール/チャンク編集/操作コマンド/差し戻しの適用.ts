import type { ワールド編集状態 } from '../編集モデル/index.ts'
import { 道路対象の道路一覧を取り出す, 道路対象の道路スプラインを取り出す } from '../編集モデル/index.ts'
import type { 差し戻し断片 } from './差し戻し断片.ts'
import { 地形と建物の差し戻し断片か, 地形と建物の差し戻しを適用する } from './地形と建物の差し戻しの適用.ts'
import { 見下ろし図の差し戻し断片か, 見下ろし図の差し戻しを適用する } from './見下ろし図の差し戻しの適用.ts'

// 差し戻し断片の情報に基づき、編集状態を変更前の値へ復元する。断片の直和が分かれている側(地形と建物・見下ろし図)は
// それぞれの適用へ振り分け、ここでは道路の側と、道路の変更に伴う泥の焼き直しを戻す。
export function 差し戻しを適用する(状態: ワールド編集状態, 断片: 差し戻し断片): void {
    if (見下ろし図の差し戻し断片か(断片)) {
        見下ろし図の差し戻しを適用する(状態, 断片)
        return
    }
    if (地形と建物の差し戻し断片か(断片)) {
        地形と建物の差し戻しを適用する(状態, 断片)
        return
    }
    switch (断片.種類) {
        case '道路を追加する': {
            道路対象の道路一覧を取り出す(状態, 断片.対象).削除する(断片.対象.値.道路添字)
            return
        }
        case '道路を削除する': {
            道路対象の道路一覧を取り出す(状態, 断片.対象).添字へ挿入する(断片.対象.値.道路添字, 断片.削除された道路)
            return
        }
        case '道路点を追加する': {
            道路対象の道路スプラインを取り出す(状態, 断片.対象).点を削除する(断片.追加された添字)
            return
        }
        case '道路点を挿入する': {
            道路対象の道路スプラインを取り出す(状態, 断片.対象).点を削除する(断片.挿入された添字)
            return
        }
        case '道路点を移動する': {
            道路対象の道路スプラインを取り出す(状態, 断片.対象).点を移動する(断片.添字, 断片.変更前位置)
            return
        }
        case '道路点を削除する': {
            道路対象の道路スプラインを取り出す(状態, 断片.対象).点を添字へ挿入する(断片.添字, 断片.削除された位置)
            return
        }
        case '道路の変更に伴う泥の焼き直し': {
            const チャンク = 状態.チャンクを取得する(断片.チャンク座標)
            チャンク.地表材質.材質データを置き換える(断片.変更前材質データ)
            チャンク.地表材質.道路の泥の被覆の記録を写しから戻す(断片.変更前の道路の泥の被覆の記録)
            差し戻しを適用する(状態, 断片.内側の道路の差し戻し)
            return
        }
    }
    const 網羅性検査: never = 断片
    throw new Error(`未対応の差し戻し断片種類: ${JSON.stringify(網羅性検査)}`)
}
