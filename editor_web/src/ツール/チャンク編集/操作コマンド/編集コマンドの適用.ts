import type { 編集コマンド } from '../../../生成/編集資源契約.ts'
import type { ワールド編集状態 } from '../編集モデル/index.ts'
import type { 差し戻し断片 } from './差し戻し断片.ts'
import { 造成筆致を適用する, 材質の筆致を適用する } from './筆致コマンド適用.ts'
import {
    道路点を削除するコマンドを適用する,
    道路点を挿入するコマンドを適用する,
    道路点を移動するコマンドを適用する,
    道路点を追加するコマンドを適用する,
} from './道路点コマンド適用.ts'
import { 道路を削除するコマンドを適用する, 道路を追加するコマンドを適用する } from './道路の追加と削除の適用.ts'
import {
    建物を配置するコマンドを適用する,
    建物を移動するコマンドを適用する,
    建物を削除するコマンドを適用する,
} from './建物コマンド適用.ts'
import {
    散布設定を変更するコマンドを適用する,
    道路に合わせて切土盛土するコマンドを適用する,
    建物基礎を平坦化するコマンドを適用する,
    急勾配を岩肌へベイクするコマンドを適用する,
    道路下を泥へベイクするコマンドを適用する,
} from './ベイクコマンド適用.ts'
import { 道路の変更へ泥を追従させる } from './道路の変更への泥の追従.ts'
import { 見下ろし図コマンドを適用する } from './見下ろし図コマンド適用.ts'

// 編集コマンドを編集モデルへ適用し、差し戻し断片を返す。道路を変えるコマンドのときは、
// 適用した後に道路下の泥の帯の焼き直しを追従させ、その差し戻しも1つの断片へ畳む。
export function 編集コマンドを適用する(
    状態: ワールド編集状態,
    コマンド: 編集コマンド,
): 差し戻し断片 {
    return 道路の変更へ泥を追従させる(状態, コマンド, 編集コマンドを種類ごとに適用する(状態, コマンド))
}

// 編集コマンド24枝を網羅的に判定し、種類ごとの適用と差し戻し断片の生成へ振り分ける。見下ろし図の8枝は1つの振り分けへまとめる。
function 編集コマンドを種類ごとに適用する(
    状態: ワールド編集状態,
    コマンド: 編集コマンド,
): 差し戻し断片 {
    switch (コマンド.種類) {
        case '造成筆致':
            return 造成筆致を適用する(状態, コマンド.値)
        case '材質の筆致':
            return 材質の筆致を適用する(状態, コマンド.値)
        case '道路を追加する':
            return 道路を追加するコマンドを適用する(状態, コマンド.値)
        case '道路を削除する':
            return 道路を削除するコマンドを適用する(状態, コマンド.値)
        case '道路点を追加する':
            return 道路点を追加するコマンドを適用する(状態, コマンド.値)
        case '道路点を挿入する':
            return 道路点を挿入するコマンドを適用する(状態, コマンド.値)
        case '道路点を移動する':
            return 道路点を移動するコマンドを適用する(状態, コマンド.値)
        case '道路点を削除する':
            return 道路点を削除するコマンドを適用する(状態, コマンド.値)
        case '建物を配置する':
            return 建物を配置するコマンドを適用する(状態, コマンド.値)
        case '建物を移動する':
            return 建物を移動するコマンドを適用する(状態, コマンド.値)
        case '建物を削除する':
            return 建物を削除するコマンドを適用する(状態, コマンド.値)
        case '散布設定を変更する':
            return 散布設定を変更するコマンドを適用する(状態, コマンド.値)
        case '道路に合わせて切土盛土する':
            return 道路に合わせて切土盛土するコマンドを適用する(状態, コマンド.値)
        case '建物基礎を平坦化する':
            return 建物基礎を平坦化するコマンドを適用する(状態, コマンド.値)
        case '急勾配を岩肌へベイクする':
            return 急勾配を岩肌へベイクするコマンドを適用する(状態, コマンド.値)
        case '道路下を泥へベイクする':
            return 道路下を泥へベイクするコマンドを適用する(状態, コマンド.値)
        case '等高線を追加する':
        case '等高線を変更する':
        case '等高線を削除する':
        case '大升を塗る':
        case '等高線から高さ場を生成する':
        case '大升から地形を生成する':
        case '高さ場から等高線を導く':
        case '高さ場から大升を導く':
            return 見下ろし図コマンドを適用する(状態, コマンド)
    }
    const 網羅性検査: never = コマンド
    throw new Error(`未対応の編集コマンド種類: ${JSON.stringify(網羅性検査)}`)
}
