import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import type { 編集コマンド, 大域世界構造, チャンク構造 } from '../../../生成/編集資源契約.ts'
import { ワールド編集状態, 散布, 空の見下ろし図の下書き } from '../編集モデル/index.ts'
import { 編集コマンドを適用する, 差し戻しを適用する } from './index.ts'

const チャンク座標 = { x: 1, z: 0 }

function 初期状態を作る(): ワールド編集状態 {
    const 大域構造: 大域世界構造 = {
        区画割り: { 一辺のメートル: 1024, 軸あたりチャンク数: 4, チャンクあたり格子解像度: 128 },
        広域道路一覧: [],
    }
    const 状態 = new ワールド編集状態(大域構造)
    const 構造: チャンク構造 = {
        道路一覧: [{
            制御点列: [
                { x: -80, y: 0, z: -60 },
                { x: -30, y: 0, z: -20 },
                { x: 20, y: 0, z: 20 },
                { x: 75, y: 0, z: 70 },
            ],
            全幅メートル: 8,
            散布除外バッファメートル: 14,
            細分割数: 80,
        }],
        建物一覧: [],
        散布: { 最小間隔メートル: 5.5, 乱数の種: 12345n },
        散布の個体一覧: [],
        見下ろし図の下書き: 空の見下ろし図の下書き(),
    }
    状態.チャンクを登録する(チャンク座標, 構造)
    状態.選択中チャンク座標 = チャンク座標
    return 状態
}

function 散布の本数を数える(状態: ワールド編集状態): number {
    const チャンク = 状態.チャンクを取得する(チャンク座標)
    return 散布.標本化を計算する(
        チャンク.散布,
        チャンク.高さ場.一辺のメートル,
        チャンク.道路一覧.チャンクの道路一覧として取り出す(),
        チャンク.建物.一覧を取得する(),
    ).length
}

function 道路点を追加するコマンド(位置: { x: number; y: number; z: number }): 編集コマンド {
    return { 種類: '道路点を追加する', 値: { 対象: { 種類: 'チャンク', 値: { チャンク座標, 道路添字: 0 } }, 位置 } }
}

describe('道路を変えて差し戻したときの散布', () => {
    it('道路点の追加2回を差し戻すと、散布の本数が元の値へ戻ること', () => {
        const 状態 = 初期状態を作る()
        const 初期の本数 = 散布の本数を数える(状態)

        const 断片一覧 = [
            編集コマンドを適用する(状態, 道路点を追加するコマンド({ x: 100, y: 0, z: 100 })),
            編集コマンドを適用する(状態, 道路点を追加するコマンド({ x: 110, y: 0, z: 30 })),
        ]
        assert.notStrictEqual(散布の本数を数える(状態), 初期の本数, '道が伸びれば散布の本数は変わるはず')

        for (let i = 断片一覧.length - 1; i >= 0; i--) {
            差し戻しを適用する(状態, 断片一覧[i]!)
        }

        assert.strictEqual(散布の本数を数える(状態), 初期の本数, '差し戻し後の散布の本数が元の値と一致するべき')
    })

    it('道の追加と削除を差し戻しても、散布の本数が元の値へ戻ること', () => {
        const 状態 = 初期状態を作る()
        const 初期の本数 = 散布の本数を数える(状態)

        const 断片 = 編集コマンドを適用する(状態, {
            種類: '道路を追加する',
            値: {
                種類: 'チャンク',
                値: {
                    チャンク座標,
                    道路: {
                        制御点列: [{ x: -100, y: 0, z: 100 }, { x: 100, y: 0, z: -100 }],
                        全幅メートル: 8,
                        散布除外バッファメートル: 14,
                        細分割数: 80,
                    },
                },
            },
        })
        assert.notStrictEqual(散布の本数を数える(状態), 初期の本数, '道が増えれば散布の本数は変わるはず')

        差し戻しを適用する(状態, 断片)
        assert.strictEqual(散布の本数を数える(状態), 初期の本数, '差し戻し後の散布の本数が元の値と一致するべき')
    })
})
