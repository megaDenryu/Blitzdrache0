import type { チャンク座標, 編集コマンド } from '../../../生成/編集資源契約.ts'

// 道路の一覧または道路点を変える編集コマンドが、どのチャンクの道路を触るかを求める。
// 道路を触らないコマンドと、チャンクではなく大域世界の広域道路を触るコマンドはnullを返す。
// 広域道路がnullなのは、チャンクの地表材質へ泥を焼く工程がそのチャンクの道路一覧だけを見るためである。
export function 道路の変更が触るチャンク座標を求める(コマンド: 編集コマンド): チャンク座標 | null {
    switch (コマンド.種類) {
        case '道路を追加する':
            return コマンド.値.種類 === 'チャンク' ? コマンド.値.値.チャンク座標 : null
        case '道路を削除する':
        case '道路点を追加する':
        case '道路点を挿入する':
        case '道路点を移動する':
        case '道路点を削除する':
            return コマンド.値.対象.種類 === 'チャンク' ? コマンド.値.対象.値.チャンク座標 : null
        case '造成筆致':
        case '材質の筆致':
        case '建物を配置する':
        case '建物を移動する':
        case '建物を削除する':
        case '散布設定を変更する':
        case '道路に合わせて切土盛土する':
        case '建物基礎を平坦化する':
        case '急勾配を岩肌へベイクする':
        case '道路下を泥へベイクする':
        case '等高線を追加する':
        case '等高線を変更する':
        case '等高線を削除する':
        case '粗マスを塗る':
        case '等高線から高さ場を生成する':
        case '粗マスから地形を生成する':
        case '高さ場から等高線を導く':
        case '高さ場から粗マスを導く':
            return null
    }
    const 網羅性検査: never = コマンド
    throw new Error(`未対応の編集コマンド種類: ${JSON.stringify(網羅性検査)}`)
}
