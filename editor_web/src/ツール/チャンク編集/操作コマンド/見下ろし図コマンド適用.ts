import type { 編集コマンド } from '../../../生成/編集資源契約.ts'
import type { ワールド編集状態 } from '../編集モデル/index.ts'
import type { 見下ろし図の差し戻し断片 } from './差し戻し断片.ts'
import {
    等高線を追加するコマンドを適用する,
    等高線を変更するコマンドを適用する,
    等高線を削除するコマンドを適用する,
    大升を塗るコマンドを適用する,
} from './見下ろし図の下書き編集の適用.ts'
import {
    等高線から高さ場を生成するコマンドを適用する,
    大升から地形を生成するコマンドを適用する,
    高さ場から等高線を導くコマンドを適用する,
    高さ場から大升を導くコマンドを適用する,
} from './見下ろし図の生成と逆導出の適用.ts'

// 見下ろし図による地形編集の8枝。編集コマンドの適用の網羅switchは、この8枝をまとめてここへ振り分ける。
export type 見下ろし図コマンド = Extract<編集コマンド, { 種類: 見下ろし図コマンドの種類 }>

export type 見下ろし図コマンドの種類 =
    | '等高線を追加する'
    | '等高線を変更する'
    | '等高線を削除する'
    | '大升を塗る'
    | '等高線から高さ場を生成する'
    | '大升から地形を生成する'
    | '高さ場から等高線を導く'
    | '高さ場から大升を導く'

export function 見下ろし図コマンドを適用する(状態: ワールド編集状態, コマンド: 見下ろし図コマンド): 見下ろし図の差し戻し断片 {
    switch (コマンド.種類) {
        case '等高線を追加する':
            return 等高線を追加するコマンドを適用する(状態, コマンド.値)
        case '等高線を変更する':
            return 等高線を変更するコマンドを適用する(状態, コマンド.値)
        case '等高線を削除する':
            return 等高線を削除するコマンドを適用する(状態, コマンド.値)
        case '大升を塗る':
            return 大升を塗るコマンドを適用する(状態, コマンド.値)
        case '等高線から高さ場を生成する':
            return 等高線から高さ場を生成するコマンドを適用する(状態, コマンド.値)
        case '大升から地形を生成する':
            return 大升から地形を生成するコマンドを適用する(状態, コマンド.値)
        case '高さ場から等高線を導く':
            return 高さ場から等高線を導くコマンドを適用する(状態, コマンド.値)
        case '高さ場から大升を導く':
            return 高さ場から大升を導くコマンドを適用する(状態, コマンド.値)
    }
    const 網羅性検査: never = コマンド
    throw new Error(`未対応の見下ろし図コマンド種類: ${JSON.stringify(網羅性検査)}`)
}
