import type { 道路を削除する, 道路を追加する } from '../../../生成/編集資源契約.ts'
import type { ワールド編集状態, 道路の所属 } from '../編集モデル/index.ts'
import { 道路スプライン, 所属の道路一覧を取り出す, 道路対象の道路一覧を取り出す } from '../編集モデル/index.ts'
import type { 道路を削除する差し戻し, 道路を追加する差し戻し } from './差し戻し断片.ts'

// 足す道路の中身は所属ごとの枝で届くため、所属と道路スプラインをここで1組にほどく。
function 足す道路をほどく(値: 道路を追加する): { 所属: 道路の所属; 道路: 道路スプライン } {
    if (値.種類 === '広域') {
        return { 所属: { 種類: '広域' }, 道路: new 道路スプライン(値.値.道路) }
    }
    return {
        所属: { 種類: 'チャンク', チャンク座標: { ...値.値.チャンク座標 } },
        道路: new 道路スプライン(値.値.道路),
    }
}

function 追加した道路の道路対象を作る(所属: 道路の所属, 道路添字: number): 道路を追加する差し戻し['対象'] {
    if (所属.種類 === '広域') return { 種類: '広域', 値: { 道路添字 } }
    return { 種類: 'チャンク', 値: { チャンク座標: { ...所属.チャンク座標 }, 道路添字 } }
}

export function 道路を追加するコマンドを適用する(状態: ワールド編集状態, 値: 道路を追加する): 道路を追加する差し戻し {
    const { 所属, 道路 } = 足す道路をほどく(値)
    const 道路添字 = 所属の道路一覧を取り出す(状態, 所属).末尾へ追加する(道路)
    return {
        種類: '道路を追加する',
        対象: 追加した道路の道路対象を作る(所属, 道路添字),
    }
}

export function 道路を削除するコマンドを適用する(状態: ワールド編集状態, 値: 道路を削除する): 道路を削除する差し戻し {
    const 一覧 = 道路対象の道路一覧を取り出す(状態, 値.対象)
    const 削除された道路 = 一覧.削除する(値.対象.値.道路添字)
    return {
        種類: '道路を削除する',
        対象: 値.対象,
        削除された道路,
    }
}
