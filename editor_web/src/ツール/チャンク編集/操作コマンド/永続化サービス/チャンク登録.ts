import type { プロジェクト保管庫接続 } from '../../../../境界/通信/index.ts'
import type { チャンク座標 } from '../../../../生成/編集資源契約.ts'
import { ワールド編集状態, 初期ワールド状態を生成する } from '../../編集モデル/index.ts'

// ワールド永続化サービスの読み込み系メソッドが共有する、1チャンク分の構造・高さ・材質を
// 保管庫から読み出して状態へ登録する工程。ワールド永続化サービスが保管庫を保持した上で
// 呼ぶモジュール私有ヘルパーであり、単独では公開しない。
export async function チャンクを読み込んで登録する(
    保管庫: プロジェクト保管庫接続,
    状態: ワールド編集状態,
    座標: チャンク座標,
): Promise<void> {
    const 構造結果 = await 保管庫.チャンクの構造を読む(座標)
    if (構造結果.種別 === '失敗') {
        throw new Error(`チャンク(${座標.x},${座標.z})構造の読込に失敗した: ${構造結果.エラー.種別} ${構造結果.エラー.説明}`)
    }
    if (構造結果.種別 === '成功') {
        const 高さ結果 = await 保管庫.チャンクの高さ格子を読む(座標)
        const 材質結果 = await 保管庫.チャンクの材質重みを読む(座標)
        const 高さ = 高さ結果.種別 === '成功' ? new Float32Array(高さ結果.値) : undefined
        const 材質 = 材質結果.種別 === '成功' ? new Uint8Array(材質結果.値) : undefined
        状態.チャンクを登録する(座標, 構造結果.値, 高さ, 材質)
    } else {
        const 初期 = 初期ワールド状態を生成する(座標, 状態.大域世界構造)
        const 初期チャンク = 初期.チャンクを取得する(座標)
        状態.チャンクを登録する(
            座標,
            初期チャンク.構造を取得する(),
            初期チャンク.高さ場.格子データ,
            初期チャンク.地表材質.材質データ,
        )
    }
}
