import type { 世界の区画割り } from '../../../../生成/編集資源契約.ts'

// 保管庫に保存済みの区画割りと状態側の区画割りが一致するかを確認する純粋関数。
// 不一致は復旧不能な状態不整合であるため例外にする。
export function 区画割りの整合を確認する(保存済み: 世界の区画割り, 状態側: 世界の区画割り): void {
    if (
        保存済み.一辺のメートル !== 状態側.一辺のメートル ||
        保存済み.軸あたりチャンク数 !== 状態側.軸あたりチャンク数 ||
        保存済み.チャンクあたり格子解像度 !== 状態側.チャンクあたり格子解像度
    ) {
        throw new Error(
            `大域世界構造の区画割りとチャンク状態の区画割りが一致しない: `
            + `保管庫(${保存済み.一辺のメートル}m, ${保存済み.軸あたりチャンク数}軸, 解像度${保存済み.チャンクあたり格子解像度}) `
            + `vs 状態(${状態側.一辺のメートル}m, ${状態側.軸あたりチャンク数}軸, 解像度${状態側.チャンクあたり格子解像度})`,
        )
    }
}
