import type { 大域世界構造, チャンク構造, チャンク座標 } from '../../../生成/編集資源契約.ts'
import { ワールド編集状態, 空の見下ろし図の下書き } from '../編集モデル/index.ts'

// 道路下の泥の追従を試すための、格子とワールド座標の対応が整数で割り切れるチャンクを組み立てる。
// チャンク一辺256m・格子33点・格子間隔8mであり、格子(gx,gz)のワールド座標は(gx*8-128, gz*8-128)になる。
// 試験の下ごしらえだけに使い、製品の経路からは呼ばない。

export const 試験のチャンク座標: チャンク座標 = { x: 0, z: 0 }
export const 試験の格子間隔メートル = 8
const 試験のチャンク一辺メートル = 256

// 初めの道路はz=-64mを東西へ走る1本。全幅8mのため泥半幅は6mになる。
export function 道路が1本あるチャンクの編集状態を作る(): ワールド編集状態 {
    const 大域構造: 大域世界構造 = {
        区画割り: { 一辺のメートル: 512, 軸あたりチャンク数: 2, チャンクあたり格子解像度: 32 },
        広域道路一覧: [],
    }
    const チャンク構造: チャンク構造 = {
        道路一覧: [{
            制御点列: [
                { x: -100, y: 0, z: -64 },
                { x: 100, y: 0, z: -64 },
            ],
            全幅メートル: 8,
            散布除外バッファメートル: 12,
            細分割数: 40,
        }],
        建物一覧: [],
        散布: { 最小間隔メートル: 5.0, 乱数の種: 12345n },
        散布の個体一覧: [],
        見下ろし図の下書き: 空の見下ろし図の下書き(),
    }
    const 状態 = new ワールド編集状態(大域構造)
    状態.チャンクを登録する(試験のチャンク座標, チャンク構造)
    状態.選択中チャンク座標 = 試験のチャンク座標
    return 状態
}

export function ワールド座標の画素番号を求める(wx: number, wz: number): number {
    const 頂点数 = 試験のチャンク一辺メートル / 試験の格子間隔メートル + 1
    const gx = Math.round((wx + 試験のチャンク一辺メートル / 2) / 試験の格子間隔メートル)
    const gz = Math.round((wz + 試験のチャンク一辺メートル / 2) / 試験の格子間隔メートル)
    return gz * 頂点数 + gx
}
