export function 散布設定を変更するコマンドを適用する(状態: ワールド編集状態, 値: 散布設定を変更する): 散布設定を変更する差し戻し {
    const チャンク = 状態.チャンクを取得する(値.チャンク座標)
    const 変更前設定 = { ...チャンク.散布 }
    チャンク.散布 = { 最小間隔メートル: 値.新しい設定.最小間隔メートル, 乱数の種: 値.新しい設定.乱数の種 }
    return {
        種類: '散布設定を変更する',
        チャンク座標: { ...値.チャンク座標 },
        変更前設定,
    }
}

