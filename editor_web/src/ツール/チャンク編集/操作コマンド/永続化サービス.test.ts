import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import type { 大域世界構造, チャンク座標, チャンク構造 } from '../../../生成/編集資源契約.ts'
import type { プロジェクト保管庫接続, 読込結果, 保存結果 } from '../../../境界/通信/index.ts'
import { 読込成功, 読込無し, 保存成功, 保存状態サービス, 状態通知付き保管庫接続 } from '../../../境界/通信/index.ts'
import { ワールド永続化サービス } from './永続化サービス.ts'

class 偽保管庫 implements プロジェクト保管庫接続 {
    public 大域構造: 大域世界構造 | null = null
    public 保存呼出順序: string[] = []

    public async 大域世界の構造を読む(): Promise<読込結果<大域世界構造>> {
        return this.大域構造 !== null ? 読込成功(this.大域構造) : 読込無し()
    }
    public async 大域世界の構造を保存する(構造: 大域世界構造): Promise<保存結果> {
        this.大域構造 = 構造
        this.保存呼出順序.push('大域世界構造')
        return 保存成功()
    }
    public async 大域世界の高さ格子を読む(): Promise<読込結果<ArrayBufferLike>> { return 読込無し() }
    public async 大域世界の高さ格子を保存する(): Promise<保存結果> { this.保存呼出順序.push('大域世界高さ格子'); return 保存成功() }
    public async チャンクの構造を読む(): Promise<読込結果<チャンク構造>> { return 読込無し() }
    public async チャンクの構造を保存する(): Promise<保存結果> { this.保存呼出順序.push('チャンク構造'); return 保存成功() }
    public async チャンクの高さ格子を読む(): Promise<読込結果<ArrayBufferLike>> { return 読込無し() }
    public async チャンクの高さ格子を保存する(): Promise<保存結果> { this.保存呼出順序.push('チャンク高さ格子'); return 保存成功() }
    public async チャンクの材質重みを読む(): Promise<読込結果<ArrayBufferLike>> { return 読込無し() }
    public async チャンクの材質重みを保存する(): Promise<保存結果> { this.保存呼出順序.push('チャンク材質重み'); return 保存成功() }
}

describe('ワールド永続化の大域世界構造整合テスト', () => {
    it('保存済みの大域世界構造があるとき、その区画割りに基づく頂点数のチャンクが生成されること', async () => {
        const 保管庫 = new 偽保管庫()
        保管庫.大域構造 = {
            区画割り: { 一辺のメートル: 512, 軸あたりチャンク数: 2, チャンクあたり格子解像度: 64 },
            広域道路一覧: [{ 制御点列: [], 全幅メートル: 8, 細分割数: 80 }],
        }
        const 座標: チャンク座標 = { x: 0, z: 0 }
        const { 状態, 結果種別 } = await new ワールド永続化サービス(保管庫).チャンクを読み込む(座標)
        assert.strictEqual(結果種別, '読込成功')
        const チャンク = 状態.チャンクを取得する(座標)
        assert.strictEqual(チャンク.高さ場.解像度, 65, '保存済み区画割りの解像度+1になること')
    })

    it('保管庫に大域世界構造が無いとき、チャンク保存で大域構造のみ保存され大域高さ格子は保存されないこと', async () => {
        const 偽 = new 偽保管庫()
        const サービス = new 保存状態サービス()
        const 保管庫 = new 状態通知付き保管庫接続(偽, サービス)
        const 永続化 = new ワールド永続化サービス(保管庫)
        const 座標: チャンク座標 = { x: 0, z: 0 }
        const { 状態 } = await 永続化.チャンクを読み込む(座標)

        assert.strictEqual(サービス.大域状態を取得する().文言, '未保存(初期生成)')
        await 永続化.保存する(状態)

        assert.strictEqual(サービス.大域状態を取得する().文言, '保存完了', '大域状態が保存完了へ更新されること')
        assert.strictEqual(サービス.チャンク状態を取得する(座標).文言, '保存完了')
        assert.deepStrictEqual(偽.保存呼出順序, ['大域世界構造', 'チャンク構造', 'チャンク高さ格子', 'チャンク材質重み'])
    })

    it('保管庫に大域世界構造が既にあるとき、チャンク保存で既存大域構造が上書きされず高さ格子も書かれないこと', async () => {
        const 偽 = new 偽保管庫()
        const 既存道路点 = [{ x: 10, y: 0, z: 20 }]
        偽.大域構造 = {
            区画割り: { 一辺のメートル: 1024, 軸あたりチャンク数: 4, チャンクあたり格子解像度: 128 },
            広域道路一覧: [{ 制御点列: 既存道路点, 全幅メートル: 12, 細分割数: 100 }],
        }
        const 永続化 = new ワールド永続化サービス(偽)
        const 座標: チャンク座標 = { x: 0, z: 0 }
        const { 状態 } = await 永続化.チャンクを読み込む(座標)

        // 状態側の大域道路を改変しても、チャンク保存で保管庫の大域構造は上書きされないこと
        状態.広域道路一覧.道路を取り出す(0).制御点列.push({ x: 999, y: 999, z: 999 })
        await 永続化.保存する(状態)

        assert.deepStrictEqual(偽.大域構造.広域道路一覧[0]?.制御点列, 既存道路点, '保管庫の広域道路が上書きされず保持されること')
        assert.deepStrictEqual(偽.保存呼出順序, ['チャンク構造', 'チャンク高さ格子', 'チャンク材質重み'], '大域構造も大域高さ格子も保存されないこと')
    })

    it('保管庫の大域区画割りとチャンク状態の区画割りが不一致のとき、チャンク保存が拒否されること', async () => {
        const 偽 = new 偽保管庫()
        偽.大域構造 = {
            区画割り: { 一辺のメートル: 512, 軸あたりチャンク数: 2, チャンクあたり格子解像度: 64 },
            広域道路一覧: [{ 制御点列: [], 全幅メートル: 8, 細分割数: 80 }],
        }
        const 永続化 = new ワールド永続化サービス(偽)
        const 座標: チャンク座標 = { x: 0, z: 0 }
        const { 状態 } = await 永続化.チャンクを読み込む(座標)

        // 状態の区画割りを不一致に変更する
        状態.区画割り.一辺のメートル = 1024
        await assert.rejects(
            async () => 永続化.保存する(状態),
            /区画割りとチャンク状態の区画割りが一致しない/,
        )
    })
})
