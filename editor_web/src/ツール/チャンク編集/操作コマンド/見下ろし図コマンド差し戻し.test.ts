import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 編集コマンドを適用する, 差し戻しを適用する } from './index.ts'
import {
    見下ろし図の試験のチャンク座標 as チャンク座標,
    起伏のあるチャンクの編集状態を作る,
    正方形の等高線,
    見下ろし図の8枝を通るコマンド列,
} from './見下ろし図の試験の下ごしらえ.ts'

describe('見下ろし図コマンドの適用と差し戻し', () => {
    it('8枝すべての適用と差し戻しで高さ場・材質・下書き・揃いが元へ戻ること', () => {
        const 状態 = 起伏のあるチャンクの編集状態を作る()
        const チャンク = 状態.チャンクを取得する(チャンク座標)
        const 初期高さ = new Float32Array(チャンク.高さ場.格子データ)
        const 初期材質 = new Uint8Array(チャンク.地表材質.材質データ)
        const 初期下書き = チャンク.下書き.契約の形で取り出す()
        assert.strictEqual(チャンク.下書きと正本の揃い, '未確認')

        const 断片一覧 = 見下ろし図の8枝を通るコマンド列().map((コマンド) => 編集コマンドを適用する(状態, コマンド))
        assert.ok(チャンク.下書き.等高線一覧を取得する().length > 0, '導いた等高線が下書きに入るべき')
        assert.strictEqual(チャンク.下書き.粗マスの一辺の升目数を取得する(), 4)
        assert.strictEqual(チャンク.下書き.粗マスの塗り一覧を取得する().length, 64)
        assert.strictEqual(チャンク.下書きと正本の揃い, '揃っている')
        assert.notDeepStrictEqual(new Float32Array(チャンク.高さ場.格子データ), 初期高さ)

        for (let i = 断片一覧.length - 1; i >= 0; i--) 差し戻しを適用する(状態, 断片一覧[i]!)

        assert.deepStrictEqual(new Float32Array(チャンク.高さ場.格子データ), 初期高さ)
        assert.deepStrictEqual(new Uint8Array(チャンク.地表材質.材質データ), 初期材質)
        assert.deepStrictEqual(チャンク.下書き.契約の形で取り出す(), 初期下書き)
        assert.strictEqual(チャンク.下書きと正本の揃い, '未確認')
    })

    it('下書きの編集で「下書きが新しい」、生成で「揃っている」、筆致とベイクで「正本が新しい」になり差し戻しで戻ること', () => {
        const 状態 = 起伏のあるチャンクの編集状態を作る()
        const チャンク = 状態.チャンクを取得する(チャンク座標)
        編集コマンドを適用する(状態, { 種類: '等高線を追加する', 値: { チャンク座標, 等高線: 正方形の等高線(64, 9) } })
        assert.strictEqual(チャンク.下書きと正本の揃い, '下書きが新しい')
        編集コマンドを適用する(状態, { 種類: '等高線から高さ場を生成する', 値: { チャンク座標 } })
        assert.strictEqual(チャンク.下書きと正本の揃い, '揃っている')
        const 筆致の断片 = 編集コマンドを適用する(状態, { 種類: '造成筆致', 値: { 種別: '盛る', 通過点列: [{ x: 0, y: 0, z: 0 }], 半径メートル: 15, 強さ: 3 } })
        assert.strictEqual(チャンク.下書きと正本の揃い, '正本が新しい')
        差し戻しを適用する(状態, 筆致の断片)
        assert.strictEqual(チャンク.下書きと正本の揃い, '揃っている')
        const ベイクの断片 = 編集コマンドを適用する(状態, { 種類: '急勾配を岩肌へベイクする', 値: { チャンク座標 } })
        assert.strictEqual(チャンク.下書きと正本の揃い, '正本が新しい')
        差し戻しを適用する(状態, ベイクの断片)
        assert.strictEqual(チャンク.下書きと正本の揃い, '揃っている')
    })

    it('等高線が無いまま生成すると理由の文で拒否されること', () => {
        const 状態 = 起伏のあるチャンクの編集状態を作る()
        assert.throws(() => 編集コマンドを適用する(状態, { 種類: '等高線から高さ場を生成する', 値: { チャンク座標 } }), /等高線が1本も無い/)
    })
})
