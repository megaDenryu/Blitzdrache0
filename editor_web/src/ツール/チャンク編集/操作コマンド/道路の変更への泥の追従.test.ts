import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import type { 編集コマンド } from '../../../生成/編集資源契約.ts'
import { 編集コマンドを適用する, 差し戻しを適用する } from './index.ts'
import {
    ワールド座標の画素番号を求める,
    試験のチャンク座標,
    道路が1本あるチャンクの編集状態を作る,
} from './道路の変更への泥の追従の下ごしらえ.ts'

const 泥の成分番号 = 1
const 旧帯の上の点 = { x: 0, z: -64 }
const 新帯の上の点 = { x: 0, z: 0 }

// 道路点0を(-100,-64)から(-100,64)へ動かす。道はz=-64の東西線から、(0,0)を通る斜めの線へ変わる。
const 道路点を移動するコマンド: 編集コマンド = {
    種類: '道路点を移動する',
    値: {
        対象: { 種類: 'チャンク', 値: { チャンク座標: 試験のチャンク座標, 道路添字: 0 } },
        添字: 0,
        新しい位置: { x: -100, y: 0, z: 64 },
    },
}

function 泥の重みを読む(材質データ: Uint8Array, 点: { x: number; z: number }): number {
    return 材質データ[ワールド座標の画素番号を求める(点.x, 点.z) * 4 + 泥の成分番号] ?? 0
}

describe('道路の変更への道路下の泥の追従', () => {
    it('道路点を動かすと泥の帯が新しい位置へ移り、古い位置が焼く前の材質へ戻ること', () => {
        const 状態 = 道路が1本あるチャンクの編集状態を作る()
        const 地表材質 = 状態.チャンクを取得する(試験のチャンク座標).地表材質
        const 焼く前の材質データ = new Uint8Array(地表材質.材質データ)

        編集コマンドを適用する(状態, { 種類: '道路下を泥へベイクする', 値: { チャンク座標: 試験のチャンク座標 } })
        assert.strictEqual(泥の重みを読む(地表材質.材質データ, 旧帯の上の点), 255, '焼き直しで古い道の直下が泥100%になるべき')

        編集コマンドを適用する(状態, 道路点を移動するコマンド)
        assert.strictEqual(泥の重みを読む(地表材質.材質データ, 新帯の上の点), 255, '動かした後の道の直下が泥100%になるべき')
        assert.strictEqual(
            泥の重みを読む(地表材質.材質データ, 旧帯の上の点),
            泥の重みを読む(焼く前の材質データ, 旧帯の上の点),
            '古い帯の画素が泥を焼く前の材質へ戻るべき',
        )
    })

    it('道路点の移動を差し戻すと泥の帯も動かす前へ戻ること', () => {
        const 状態 = 道路が1本あるチャンクの編集状態を作る()
        const 地表材質 = 状態.チャンクを取得する(試験のチャンク座標).地表材質

        編集コマンドを適用する(状態, { 種類: '道路下を泥へベイクする', 値: { チャンク座標: 試験のチャンク座標 } })
        const 動かす前の材質データ = new Uint8Array(地表材質.材質データ)

        const 断片 = 編集コマンドを適用する(状態, 道路点を移動するコマンド)
        差し戻しを適用する(状態, 断片)

        assert.deepStrictEqual(地表材質.材質データ, 動かす前の材質データ, '差し戻しで材質データが動かす前とバイト一致するべき')
        const 制御点 = 状態.チャンクを取得する(試験のチャンク座標).道路一覧.道路を取り出す(0).制御点列[0]
        assert.deepStrictEqual(制御点, { x: -100, y: 0, z: -64 }, '差し戻しで道路点も動かす前へ戻るべき')
    })

    it('帯の外へ塗った手塗りが焼き直しで消えないこと', () => {
        const 状態 = 道路が1本あるチャンクの編集状態を作る()
        const 地表材質 = 状態.チャンクを取得する(試験のチャンク座標).地表材質
        const 手塗りの点 = { x: 0, z: 64 }

        編集コマンドを適用する(状態, { 種類: '道路下を泥へベイクする', 値: { チャンク座標: 試験のチャンク座標 } })
        編集コマンドを適用する(状態, {
            種類: '材質の筆致',
            値: { 層: '岩', 通過点列: [{ x: 手塗りの点.x, y: 0, z: 手塗りの点.z }], 半径メートル: 10, 流量: 1.0 },
        })
        const 手塗りの画素先頭 = ワールド座標の画素番号を求める(手塗りの点.x, 手塗りの点.z) * 4
        const 手塗り直後の画素 = 地表材質.材質データ.slice(手塗りの画素先頭, 手塗りの画素先頭 + 4)
        assert.ok((手塗り直後の画素[2] ?? 0) > 0, '手塗りで岩の重みが乗るべき')

        編集コマンドを適用する(状態, 道路点を移動するコマンド)

        const 焼き直し後の画素 = 地表材質.材質データ.slice(手塗りの画素先頭, 手塗りの画素先頭 + 4)
        assert.deepStrictEqual(焼き直し後の画素, 手塗り直後の画素, '帯の外の手塗りは焼き直しで触られないべき')
    })

    it('追従しない方針では道路点を動かしても材質が変わらないこと', () => {
        const 状態 = 道路が1本あるチャンクの編集状態を作る()
        状態.道路の泥の追従方針 = '追従しない'
        const 地表材質 = 状態.チャンクを取得する(試験のチャンク座標).地表材質

        編集コマンドを適用する(状態, { 種類: '道路下を泥へベイクする', 値: { チャンク座標: 試験のチャンク座標 } })
        const 動かす前の材質データ = new Uint8Array(地表材質.材質データ)
        編集コマンドを適用する(状態, 道路点を移動するコマンド)

        assert.deepStrictEqual(地表材質.材質データ, 動かす前の材質データ, '追従しない方針では焼き直しが走らないべき')
        assert.strictEqual(泥の重みを読む(地表材質.材質データ, 旧帯の上の点), 255, '手動で焼いた古い帯の泥が残るべき')
    })
})
