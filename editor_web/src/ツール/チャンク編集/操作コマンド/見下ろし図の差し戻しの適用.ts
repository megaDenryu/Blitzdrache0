import type { ワールド編集状態 } from '../編集モデル/index.ts'
import type { 差し戻し断片, 見下ろし図の差し戻し断片 } from './差し戻し断片.ts'

// 見下ろし図の8枝の差し戻し。差し戻しの適用の網羅switchは、この8枝をまとめてここへ振り分ける。
// どの枝も最後に下書きと正本の揃いを変更前へ戻す。

export function 見下ろし図の差し戻し断片か(断片: 差し戻し断片): 断片 is 見下ろし図の差し戻し断片 {
    switch (断片.種類) {
        case '等高線を追加する':
        case '等高線を変更する':
        case '等高線を削除する':
        case '大升を塗る':
        case '等高線から高さ場を生成する':
        case '大升から地形を生成する':
        case '高さ場から等高線を導く':
        case '高さ場から大升を導く':
            return true
        default:
            return false
    }
}

export function 見下ろし図の差し戻しを適用する(状態: ワールド編集状態, 断片: 見下ろし図の差し戻し断片): void {
    const チャンク = 状態.チャンクを取得する(断片.チャンク座標)
    switch (断片.種類) {
        case '等高線を追加する':
            チャンク.下書き.等高線を削除する(断片.追加した添字)
            break
        case '等高線を変更する':
            チャンク.下書き.等高線を変更する(断片.添字, 断片.変更前の等高線)
            break
        case '等高線を削除する':
            チャンク.下書き.等高線を添字へ挿入する(断片.添字, 断片.削除した等高線)
            break
        case '大升を塗る':
        case '高さ場から大升を導く':
            チャンク.下書き.大升の塗り全体を置き換える(断片.変更前の大升の一辺の升目数, 断片.変更前の大升の塗り一覧)
            break
        case '等高線から高さ場を生成する':
            チャンク.高さ場.格子データを置き換える(断片.変更前格子データ)
            break
        case '大升から地形を生成する':
            チャンク.高さ場.格子データを置き換える(断片.変更前格子データ)
            チャンク.地表材質.材質データを置き換える(断片.変更前材質データ)
            break
        case '高さ場から等高線を導く':
            チャンク.下書き.等高線一覧を置き換える(断片.変更前の等高線一覧)
            break
        default: {
            const 網羅性検査: never = 断片
            throw new Error(`未対応の見下ろし図の差し戻し断片種類: ${JSON.stringify(網羅性検査)}`)
        }
    }
    チャンク.下書きと正本の揃い = 断片.変更前の揃い
}
