import { describe, it } from "node:test"
import assert from "node:assert/strict"
import { ワールド編集状態 } from "../編集モデル/index.ts"
import { 編集コマンドを適用する, 差し戻しを適用する } from "./index.ts"
import type { 編集コマンド, 大域世界構造, チャンク構造 } from "../../../生成/編集資源契約.ts"

function 初期状態を作成する(): ワールド編集状態 {
    const 大域構造: 大域世界構造 = {
        区画割り: { 一辺のメートル: 512, 軸あたりチャンク数: 2, チャンクあたり格子解像度: 33 },
        広域道路一覧: [{
            制御点列: [
                { x: -100, y: 0, z: 0 },
                { x: 100, y: 0, z: 0 },
            ],
            全幅メートル: 12,
            細分割数: 20,
        }],
    }
    const 状態 = new ワールド編集状態(大域構造)
    const チャンク構造00: チャンク構造 = {
        道路一覧: [{
            制御点列: [
                { x: -50, y: 5, z: -50 },
                { x: 50, y: 5, z: 50 },
            ],
            全幅メートル: 6,
            散布除外バッファメートル: 10,
            細分割数: 20,
        }],
        建物一覧: [],
        散布: { 最小間隔メートル: 5.0, 乱数の種: 12345n },
    }
    状態.チャンクを登録する({ x: 0, z: 0 }, チャンク構造00)
    return 状態
}

describe("操作コマンド層の適用と差し戻し", () => {
    it("16枝すべての編集コマンドの適用と差し戻しで状態が完全に復元されること", () => {
        const 状態 = 初期状態を作成する()
        const チャンク座標 = { x: 0, z: 0 }
        状態.選択中チャンク座標 = チャンク座標

        const コマンド一覧: Array<編集コマンド> = [
            { 種類: "造成筆致", 値: { 種別: "盛る", 通過点列: [{ x: 0, y: 0, z: 0 }], 半径メートル: 15, 強さ: 3.5 } },
            { 種類: "材質の筆致", 値: { 層: "泥", 通過点列: [{ x: 0, y: 0, z: 0 }], 半径メートル: 10, 流量: 0.5 } },
            { 種類: "道路を追加する", 値: { 種類: "チャンク", 値: { チャンク座標, 道路: { 制御点列: [{ x: 90, y: 5, z: 90 }], 全幅メートル: 6, 散布除外バッファメートル: 10, 細分割数: 20 } } } },
            { 種類: "道路を削除する", 値: { 対象: { 種類: "チャンク", 値: { チャンク座標, 道路添字: 1 } } } },
            { 種類: "道路点を追加する", 値: { 対象: { 種類: "チャンク", 値: { チャンク座標, 道路添字: 0 } }, 位置: { x: 20, y: 5, z: 20 } } },
            { 種類: "道路点を挿入する", 値: { 対象: { 種類: "チャンク", 値: { チャンク座標, 道路添字: 0 } }, 添字: 1, 位置: { x: 0, y: 5, z: 0 } } },
            { 種類: "道路点を移動する", 値: { 対象: { 種類: "チャンク", 値: { チャンク座標, 道路添字: 0 } }, 添字: 0, 新しい位置: { x: -60, y: 6, z: -60 } } },
            { 種類: "道路点を削除する", 値: { 対象: { 種類: "チャンク", 値: { チャンク座標, 道路添字: 0 } }, 添字: 1 } },
            { 種類: "建物を配置する", 値: { チャンク座標, 建物: { 識別子: "家屋_A", 種別: "家屋", 位置: { x: 10, y: 2, z: 10 }, 向きラジアン: 0, 基礎半径メートル: 6, なじみ半径メートル: 12 } } },
            { 種類: "建物を移動する", 値: { チャンク座標, 識別子: "家屋_A", 新しい位置: { x: 15, y: 3, z: 15 }, 新しい向きラジアン: 1.0 } },
            { 種類: "建物を削除する", 値: { チャンク座標, 識別子: "家屋_A" } },
            { 種類: "散布設定を変更する", 値: { チャンク座標, 新しい設定: { 最小間隔メートル: 8.0, 乱数の種: 987654n } } },
            { 種類: "道路に合わせて切土盛土する", 値: { チャンク座標 } },
            { 種類: "建物を配置する", 値: { チャンク座標, 建物: { 識別子: "塔_B", 種別: "塔", 位置: { x: -10, y: 8, z: -10 }, 向きラジアン: 0, 基礎半径メートル: 5, なじみ半径メートル: 10 } } },
            { 種類: "建物基礎を平坦化する", 値: { チャンク座標, 建物識別子: "塔_B" } },
            { 種類: "急勾配を岩肌へベイクする", 値: { チャンク座標 } },
            { 種類: "道路下を泥へベイクする", 値: { チャンク座標 } },
        ]

        const チャンク = 状態.チャンクを取得する(チャンク座標)
        const 初期高さバイト列 = new Uint8Array(チャンク.高さ場.格子データ.buffer.slice(0))
        const 初期材質バイト列 = new Uint8Array(チャンク.地表材質.材質データ.buffer.slice(0))
        const 初期道路点列 = チャンク.道路一覧.道路を取り出す(0).制御点列.map((p) => ({ ...p }))
        const 初期道路本数 = チャンク.道路一覧.件数
        const 初期散布 = { ...チャンク.散布 }

        const 断片一覧 = コマンド一覧.map((cmd) => 編集コマンドを適用する(状態, cmd))

        for (let i = 断片一覧.length - 1; i >= 0; i--) {
            差し戻しを適用する(状態, 断片一覧[i]!)
        }

        const 復元高さバイト列 = new Uint8Array(チャンク.高さ場.格子データ.buffer.slice(0))
        const 復元材質バイト列 = new Uint8Array(チャンク.地表材質.材質データ.buffer.slice(0))
        assert.deepStrictEqual(復元高さバイト列, 初期高さバイト列, "高さ場が初期状態とバイト一致するべき")
        assert.deepStrictEqual(復元材質バイト列, 初期材質バイト列, "地表材質が初期状態とバイト一致するべき")
        assert.strictEqual(チャンク.道路一覧.件数, 初期道路本数, "道路の本数が初期状態と一致するべき")
        assert.deepStrictEqual(チャンク.道路一覧.道路を取り出す(0).制御点列, 初期道路点列, "道路制御点が初期状態と一致するべき")
        assert.deepStrictEqual(チャンク.散布, 初期散布, "散布設定が初期状態と一致するべき")
        assert.strictEqual(チャンク.建物.一覧を取得する().length, 0, "建物一覧が初期状態(0件)と一致するべき")
    })
})
