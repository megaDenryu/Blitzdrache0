import type { 編集コマンド } from '../../../生成/編集資源契約.ts'
import type { ワールド編集状態 } from '../編集モデル/index.ts'
import type { 差し戻し断片, 道路の差し戻し断片 } from './差し戻し断片.ts'
import { 道路の変更が触るチャンク座標を求める } from './道路の変更が触るチャンク座標.ts'

// 包む相手が道路の側の断片であることを、道路の変更コマンドだという前提とは別に確かめる。
function 道路の差し戻し断片か(断片: 差し戻し断片): 断片 is 道路の差し戻し断片 {
    switch (断片.種類) {
        case '道路を追加する':
        case '道路を削除する':
        case '道路点を追加する':
        case '道路点を挿入する':
        case '道路点を移動する':
        case '道路点を削除する':
            return true
        default:
            return false
    }
}

// 道路の変更コマンドを適用した直後に、そのチャンクの道路下の泥の帯を焼き直す。
// 道路の変更そのものは地表材質を触らないため、焼き直す直前の材質がそのまま「変更前の材質」になる。
// 方針が追従しないとき、および道路を触らないコマンド・広域道路のコマンドのときは、
// 受け取った差し戻し断片をそのまま返す。
export function 道路の変更へ泥を追従させる(
    状態: ワールド編集状態,
    コマンド: 編集コマンド,
    断片: 差し戻し断片,
): 差し戻し断片 {
    if (状態.道路の泥の追従方針 === '追従しない') return 断片
    const チャンク座標 = 道路の変更が触るチャンク座標を求める(コマンド)
    if (チャンク座標 === null) return 断片
    if (!道路の差し戻し断片か(断片)) {
        throw new Error(`道路の変更コマンドが道路の差し戻し断片を返していない: 断片の種類=${断片.種類}`)
    }
    const チャンク = 状態.チャンクを取得する(チャンク座標)
    const 変更前材質データ = new Uint8Array(チャンク.地表材質.材質データ)
    const 変更前の道路の泥の被覆の記録 = チャンク.地表材質.道路の泥の被覆の記録の写しを取る()
    チャンク.地表材質.道路下の泥の帯を焼き直す(チャンク.道路一覧.チャンクの道路一覧として取り出す())
    return {
        種類: '道路の変更に伴う泥の焼き直し',
        チャンク座標: { ...チャンク座標 },
        変更前材質データ,
        変更前の道路の泥の被覆の記録,
        内側の道路の差し戻し: 断片,
    }
}
