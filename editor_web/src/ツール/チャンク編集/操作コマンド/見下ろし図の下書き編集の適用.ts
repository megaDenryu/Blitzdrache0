import type { 等高線を追加する, 等高線を変更する, 等高線を削除する, 大升を塗る } from '../../../生成/編集資源契約.ts'
import type { ワールド編集状態 } from '../編集モデル/index.ts'
import type {
    等高線を追加する差し戻し,
    等高線を変更する差し戻し,
    等高線を削除する差し戻し,
    大升を塗る差し戻し,
} from './差し戻し断片.ts'

// 見下ろし図の下書きを編集する4枝の適用。下書きだけが変わり正本は変わらないため、揃いは「下書きが新しい」になる。
// 参照: `_doc/設計/見下ろし図による地形編集.md`「判断2」。

export function 等高線を追加するコマンドを適用する(状態: ワールド編集状態, 値: 等高線を追加する): 等高線を追加する差し戻し {
    const チャンク = 状態.チャンクを取得する(値.チャンク座標)
    const 変更前の揃い = チャンク.下書きと正本の揃い
    const 追加した添字 = チャンク.下書き.等高線を追加する(値.等高線)
    チャンク.下書きと正本の揃い = '下書きが新しい'
    return { 種類: '等高線を追加する', チャンク座標: { ...値.チャンク座標 }, 追加した添字, 変更前の揃い }
}

export function 等高線を変更するコマンドを適用する(状態: ワールド編集状態, 値: 等高線を変更する): 等高線を変更する差し戻し {
    const チャンク = 状態.チャンクを取得する(値.チャンク座標)
    const 変更前の揃い = チャンク.下書きと正本の揃い
    const 変更前の等高線 = チャンク.下書き.等高線を変更する(値.添字, 値.等高線)
    チャンク.下書きと正本の揃い = '下書きが新しい'
    return { 種類: '等高線を変更する', チャンク座標: { ...値.チャンク座標 }, 添字: 値.添字, 変更前の等高線, 変更前の揃い }
}

export function 等高線を削除するコマンドを適用する(状態: ワールド編集状態, 値: 等高線を削除する): 等高線を削除する差し戻し {
    const チャンク = 状態.チャンクを取得する(値.チャンク座標)
    const 変更前の揃い = チャンク.下書きと正本の揃い
    const 削除した等高線 = チャンク.下書き.等高線を削除する(値.添字)
    チャンク.下書きと正本の揃い = '下書きが新しい'
    return { 種類: '等高線を削除する', チャンク座標: { ...値.チャンク座標 }, 添字: 値.添字, 削除した等高線, 変更前の揃い }
}

// 一辺が変わると塗りが空になるため、差し戻しは一辺と塗りの全体を持つ。
export function 大升を塗るコマンドを適用する(状態: ワールド編集状態, 値: 大升を塗る): 大升を塗る差し戻し {
    const チャンク = 状態.チャンクを取得する(値.チャンク座標)
    const 変更前の揃い = チャンク.下書きと正本の揃い
    const 変更前の大升の一辺の升目数 = チャンク.下書き.大升の一辺の升目数を取得する()
    const 変更前の大升の塗り一覧 = チャンク.下書き.大升の塗り一覧を取得する()
    チャンク.下書き.大升を塗る(値.大升の一辺の升目数, 値.塗り一覧)
    チャンク.下書きと正本の揃い = '下書きが新しい'
    return {
        種類: '大升を塗る',
        チャンク座標: { ...値.チャンク座標 },
        変更前の大升の一辺の升目数,
        変更前の大升の塗り一覧,
        変更前の揃い,
    }
}
