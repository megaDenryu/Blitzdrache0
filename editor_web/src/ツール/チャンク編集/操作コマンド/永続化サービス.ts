import type { プロジェクト保管庫接続 } from '../../../境界/通信/index.ts'
import type { チャンク座標, チャンク構造 } from '../../../生成/編集資源契約.ts'
import { ワールド編集状態, 初期ワールド状態を生成する } from '../編集モデル/index.ts'
import { チャンクを読み込んで登録する } from './永続化サービス/チャンク登録.ts'
import { 区画割りの整合を確認する } from './永続化サービス/区画割り整合確認.ts'

export interface ワールド読込結果 {
    readonly 状態: ワールド編集状態
    readonly 結果種別: '読込成功' | '初期生成'
}

// ワールド編集状態と保管庫の間の読込・保存を一元化するサービス。
// チャンク編集ツール(ブラウザ側)とヘッドレス側は、このサービス1つを注入して同じ実装を共有する。
export class ワールド永続化サービス {
    public constructor(private readonly _保管庫: プロジェクト保管庫接続) {}

    public async チャンクを読み込む(対象座標: チャンク座標 = { x: 0, z: 0 }): Promise<ワールド読込結果> {
        const 大域構造結果 = await this._保管庫.大域世界の構造を読む()
        if (大域構造結果.種別 === '失敗') {
            throw new Error(`大域世界構造の読込に失敗した: ${大域構造結果.エラー.種別} ${大域構造結果.エラー.説明}`)
        }
        if (大域構造結果.種別 === '無し') {
            return { 状態: 初期ワールド状態を生成する(対象座標), 結果種別: '初期生成' }
        }

        const 状態 = new ワールド編集状態(大域構造結果.値, await this._大域高さを読み込む())
        await チャンクを読み込んで登録する(this._保管庫, 状態, 対象座標)
        状態.選択中チャンク座標 = 対象座標
        return { 状態, 結果種別: '読込成功' }
    }

    public async 複数チャンクを読み込む(
        対象チャンク座標一覧: readonly チャンク座標[] = [{ x: 0, z: 0 }],
    ): Promise<ワールド編集状態> {
        const 大域構造結果 = await this._保管庫.大域世界の構造を読む()
        if (大域構造結果.種別 === '失敗') {
            throw new Error(`大域世界構造の読込に失敗した: ${大域構造結果.エラー.種別} ${大域構造結果.エラー.説明}`)
        }
        if (大域構造結果.種別 === '無し') {
            const 初期状態 = 初期ワールド状態を生成する()
            初期状態.選択中チャンク座標 = 対象チャンク座標一覧[0] ?? { x: 0, z: 0 }
            return 初期状態
        }

        const 状態 = new ワールド編集状態(大域構造結果.値, await this._大域高さを読み込む())
        for (const 座標 of 対象チャンク座標一覧) {
            await チャンクを読み込んで登録する(this._保管庫, 状態, 座標)
        }
        状態.選択中チャンク座標 = 対象チャンク座標一覧[0] ?? { x: 0, z: 0 }
        return 状態
    }

    // 注意: 大域世界の高さ格子・広域道路は大域世界の正本であり、チャンクの保存では一切書かない。
    public async 保存する(状態: ワールド編集状態): Promise<void> {
        const 大域構造結果 = await this._保管庫.大域世界の構造を読む()
        if (大域構造結果.種別 === '失敗') {
            throw new Error(`大域世界構造の読込に失敗した: ${大域構造結果.エラー.種別} ${大域構造結果.エラー.説明}`)
        }
        if (大域構造結果.種別 === '無し') {
            const 大域構造保存 = await this._保管庫.大域世界の構造を保存する(状態.大域世界構造)
            if (大域構造保存.種別 === '失敗') {
                throw new Error(`大域世界構造の保存に失敗した: ${大域構造保存.エラー.種別} ${大域構造保存.エラー.説明}`)
            }
        } else {
            区画割りの整合を確認する(大域構造結果.値.区画割り, 状態.大域世界構造.区画割り)
        }

        for (const [, チャンク] of 状態.チャンク一覧マップ) {
            await this._チャンクを保存する(チャンク.座標, チャンク.構造を取得する(), チャンク.高さ場.格子データ, チャンク.地表材質.材質データ)
        }
    }

    private async _大域高さを読み込む(): Promise<Float32Array | undefined> {
        const 結果 = await this._保管庫.大域世界の高さ格子を読む()
        return 結果.種別 === '成功' ? new Float32Array(結果.値) : undefined
    }

    private async _チャンクを保存する(
        座標: チャンク座標,
        構造: チャンク構造,
        高さ: Float32Array,
        材質: Uint8Array,
    ): Promise<void> {
        const 構造結果 = await this._保管庫.チャンクの構造を保存する(座標, 構造)
        if (構造結果.種別 === '失敗') throw new Error(`チャンク(${座標.x},${座標.z})構造の保存に失敗した: ${構造結果.エラー.種別} ${構造結果.エラー.説明}`)
        const 高さ結果 = await this._保管庫.チャンクの高さ格子を保存する(座標, 高さ.buffer)
        if (高さ結果.種別 === '失敗') throw new Error(`チャンク(${座標.x},${座標.z})高さ格子の保存に失敗した: ${高さ結果.エラー.種別} ${高さ結果.エラー.説明}`)
        const 材質結果 = await this._保管庫.チャンクの材質重みを保存する(座標, 材質.buffer)
        if (材質結果.種別 === '失敗') throw new Error(`チャンク(${座標.x},${座標.z})材質重みの保存に失敗した: ${材質結果.エラー.種別} ${材質結果.エラー.説明}`)
    }
}
