import { 編集対象の道路一覧 } from './編集モデル/index.ts'
import type { ワールド編集状態 } from './編集モデル/index.ts'
import type { チャンク編集画面部品 } from './画面/index.ts'
import type { チャンク編集状態 } from './チャンク編集状態.ts'
import type { チャンク編集操作サービス } from './チャンク編集操作サービス.ts'
import type { チャンク編集同期サービス } from './チャンク編集同期サービス.ts'
import { 道路パネル操作 } from './道路パネル操作.ts'

// 右サイドバーの道路パネルと、下パネルの棚の道を引き始めるパネルを、道路パネル操作サービスと
// 対象の道の設定変更へつなぐ。区画は違っても、どちらも同じ道の一覧を触るためここが1つで受け持つ。
// 全幅・散布除外バッファ・細分割数は「対象の道」1本にだけ効き、切土盛土は全ての道に効く。
export function 道路パネルを配線する(
    部品: チャンク編集画面部品,
    状態: チャンク編集状態,
    操作: チャンク編集操作サービス,
    同期: チャンク編集同期サービス,
    モデル: ワールド編集状態,
): void {
    const 道路一覧 = new 編集対象の道路一覧(モデル, { 種類: 'チャンク', チャンク座標: { ...状態.対象チャンク座標 } })
    const パネル操作 = new 道路パネル操作(道路一覧, 状態, 操作, 同期)

    // 対象の道が無いときスライダーは操作できないため、この関数が呼ばれるのは道が在るときだけである。
    const 対象の道へ = (設定を書き換える: (道路: ReturnType<typeof 道路一覧.道路を取り出す>) => void): void => {
        const 添字 = 状態.アクティブな道路の添字
        if (添字 === null || !道路一覧.一覧.道路が在るか(添字)) return
        設定を書き換える(道路一覧.道路を取り出す(添字))
    }

    部品.インスペクター.部品.道路.配線する({
        on全幅変更: (全幅) => {
            対象の道へ((道路) => { 道路.全幅メートル = 全幅 })
            同期.道路を同期する()
        },
        on除外バッファ変更: (バッファ) => {
            対象の道へ((道路) => { 道路.散布除外バッファメートル = バッファ })
            同期.道路を同期する()
            同期.散布を同期する()
        },
        // 細分割数は散布除外の帯を何点で標本化するかを決めるため、散布の本数も動く。
        on細分割数変更: (細分割) => {
            対象の道へ((道路) => { 道路.細分割数 = 細分割 })
            同期.道路を同期する()
            同期.散布を同期する()
        },
        on道路切土盛土: () => 操作.コマンドを実行する({
            種類: '道路に合わせて切土盛土する',
            値: { チャンク座標: { ...状態.対象チャンク座標 } },
        }),
        on選択中の道路点を削除: () => パネル操作.選択中の道路点を削除する(),
        on対象の道を削除: () => パネル操作.対象の道を削除する(),
        on全ての道を消す: () => パネル操作.全ての道を消す(),
    })

    // 棚で道を選んだら道作成モードへ移す。移さないと、押した直後に地形をクリックしても
    // 点が置かれず、押した結果が画面に返らない(エディター制作スキル第5条)。
    部品.棚.部品.道を引き始める.配線する({
        on新しい道を始める: () => {
            パネル操作.新しい道を始める()
            操作.モードを移す('道作成')
        },
    })
}
