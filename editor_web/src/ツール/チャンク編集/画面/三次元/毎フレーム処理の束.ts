import type { 描画ループ } from 'SengenThree'

export type 毎フレームの処理 = (時刻ミリ秒: number) => void

// 描画ループが受け付ける描画前処理は1つだけで、後から設定したものが前のものを黙って置き換える。
// キー入力によるカメラ移動と、マーカーの見かけの大きさをカメラ距離へ追従させる処理のように、
// 毎フレーム走らせたいものが複数あるため、ここで束ねて1つの前処理として描画ループへ渡す。
export class 毎フレーム処理の束 {
    private _処理一覧: 毎フレームの処理[] = []

    // 描画ループの唯一の前処理として自分を差し込む。呼び出しは三次元ビューの構築時の1回だけにする。
    public 描画ループへ差し込む(対象の描画ループ: 描画ループ): this {
        対象の描画ループ.前処理を設定する((時刻ミリ秒) => this._すべて実行する(時刻ミリ秒))
        return this
    }

    // 処理を束へ加え、取り外すための関数を返す。
    public 加える(処理: 毎フレームの処理): () => void {
        this._処理一覧.push(処理)
        return () => {
            this._処理一覧 = this._処理一覧.filter((登録済み) => 登録済み !== 処理)
        }
    }

    private _すべて実行する(時刻ミリ秒: number): void {
        for (const 処理 of this._処理一覧) {
            処理(時刻ミリ秒)
        }
    }
}
