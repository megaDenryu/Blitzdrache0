import type { 高さ場 } from '../../../編集モデル/index.ts'
import { ブラシ内外比, ブラシ浮上量メートル } from './ブラシ角度列.ts'

// リングの添字配列(内周・外周を交互に並べた頂点を四角形帯として結ぶ)を作る。
// 頂点の並びが変わらない限り構築時に1回だけ作ればよく、頂点位置の更新のたびに作り直さない。
export function ブラシリング添字を作る(分割数: number): Uint16Array {
    const 添字配列 = new Uint16Array(分割数 * 6)
    let 位置 = 0
    for (let i = 0; i < 分割数; i++) {
        const 次 = (i + 1) % 分割数
        const 内 = i * 2
        const 外 = i * 2 + 1
        const 次内 = 次 * 2
        const 次外 = 次 * 2 + 1
        添字配列[位置++] = 内
        添字配列[位置++] = 外
        添字配列[位置++] = 次内
        添字配列[位置++] = 次外
        添字配列[位置++] = 次内
        添字配列[位置++] = 外
    }
    return 添字配列
}

// リングの頂点位置バッファ(内周・外周を交互に並べた2*分割数点、xyzの順)を、中心位置・半径・
// 地形の高さ場から書き戻す。頂点は部品(オブジェクト)のローカル座標系で表すため、
// 中心からの相対座標として書き込む(オブジェクト自身の位置は中心X,0,中心Zへ置く前提)。
export function ブラシリング頂点を更新する(
    頂点配列: Float32Array,
    角度列: Float64Array,
    中心X: number,
    中心Z: number,
    半径メートル: number,
    地形高さ場: 高さ場,
): void {
    const 内半径 = 半径メートル * ブラシ内外比
    for (let i = 0; i < 角度列.length; i++) {
        const 角度 = 角度列[i] ?? 0
        const cos = Math.cos(角度)
        const sin = Math.sin(角度)

        const 内X = 中心X + cos * 内半径
        const 内Z = 中心Z + sin * 内半径
        const 内添字 = i * 2 * 3
        頂点配列[内添字 + 0] = 内X - 中心X
        頂点配列[内添字 + 1] = 地形高さ場.標本高さを取得する(内X, 内Z) + ブラシ浮上量メートル
        頂点配列[内添字 + 2] = 内Z - 中心Z

        const 外X = 中心X + cos * 半径メートル
        const 外Z = 中心Z + sin * 半径メートル
        const 外添字 = (i * 2 + 1) * 3
        頂点配列[外添字 + 0] = 外X - 中心X
        頂点配列[外添字 + 1] = 地形高さ場.標本高さを取得する(外X, 外Z) + ブラシ浮上量メートル
        頂点配列[外添字 + 2] = 外Z - 中心Z
    }
}
