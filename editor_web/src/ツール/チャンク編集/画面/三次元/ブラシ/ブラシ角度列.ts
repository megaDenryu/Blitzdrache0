// リング・塗り円の分割数、リングの内周比、地表からの浮上量。両ジオメトリの生成・更新で
// 共有し、頂点の対応関係(添字配列との整合)を崩さない。
export const ブラシ分割数 = 32
export const ブラシ内外比 = 0.9
export const ブラシ浮上量メートル = 0.2

// 分割数だけ等間隔に取った円周上の角度(ラジアン)を返す。ジオメトリの構築・更新の両方で
// 同じ角度列を使うことで、頂点の対応関係を崩さずにバッファへ書き戻せる。
export function ブラシ角度列を作る(分割数: number): Float64Array {
    const 角度列 = new Float64Array(分割数)
    for (let i = 0; i < 分割数; i++) {
        角度列[i] = (i / 分割数) * Math.PI * 2
    }
    return 角度列
}
