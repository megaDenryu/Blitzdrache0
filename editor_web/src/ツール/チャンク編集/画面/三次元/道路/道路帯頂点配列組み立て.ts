import type { 高さ場 } from '../../../編集モデル/index.ts'
import type { 水平位置 } from './道路中心線標本列.ts'

export interface 道路帯幾何データ {
    readonly 頂点配列: Float32Array
    readonly UV配列: Float32Array
    readonly 添字配列: Uint32Array
}

// 路面の縞模様の繰り返し回数。帯の長さに関わらずこの回数だけV座標を巻く。
const 経路方向のUV繰り返し数 = 20

// 頂点は行(進行方向)を外側、列(左端から右端)を内側にして並べる。三角形の張り方は
// 「行が進む向き × 列が右へ進む向き」で一定なため、裏返りが無ければ表向きが揃う。
function 三角形の添字配列を作る(行数: number, 列数: number): Uint32Array {
    const 添字配列 = new Uint32Array((行数 - 1) * (列数 - 1) * 6)
    let 書き込み位置 = 0
    for (let 行 = 0; 行 < 行数 - 1; 行++) {
        for (let 列 = 0; 列 < 列数 - 1; 列++) {
            const 手前 = 行 * 列数 + 列
            const 奥 = (行 + 1) * 列数 + 列
            添字配列[書き込み位置++] = 手前
            添字配列[書き込み位置++] = 奥
            添字配列[書き込み位置++] = 手前 + 1
            添字配列[書き込み位置++] = 手前 + 1
            添字配列[書き込み位置++] = 奥
            添字配列[書き込み位置++] = 奥 + 1
        }
    }
    return 添字配列
}

// 列ごとの点列(左端の列から右端の列まで)を格子とみなし、頂点・UV・三角形の添字へ組み立てる。
// 高さは水平座標から高さ場を参照して決め、Yオフセットのぶんだけ地表から浮かせる。
export function 帯の格子を幾何データへ組み立てる(
    列ごとの点列: readonly (readonly 水平位置[])[],
    高さ場モデル: 高さ場,
    Yオフセット: number,
): 道路帯幾何データ | null {
    const 列数 = 列ごとの点列.length
    const 行数 = 列ごとの点列[0]?.length ?? 0
    if (列数 < 2 || 行数 < 2) return null

    const 頂点配列 = new Float32Array(行数 * 列数 * 3)
    const UV配列 = new Float32Array(行数 * 列数 * 2)
    let 頂点添字 = 0
    for (let 行 = 0; 行 < 行数; 行++) {
        const 経路比率 = 行 / (行数 - 1)
        for (let 列 = 0; 列 < 列数; 列++) {
            const 点 = 列ごとの点列[列]?.[行]
            if (点 === undefined) return null
            頂点配列[頂点添字 * 3 + 0] = 点.x
            頂点配列[頂点添字 * 3 + 1] = 高さ場モデル.標本高さを取得する(点.x, 点.z) + Yオフセット
            頂点配列[頂点添字 * 3 + 2] = 点.z
            UV配列[頂点添字 * 2 + 0] = 列 / (列数 - 1)
            UV配列[頂点添字 * 2 + 1] = 経路比率 * 経路方向のUV繰り返し数
            頂点添字++
        }
    }
    return { 頂点配列, UV配列, 添字配列: 三角形の添字配列を作る(行数, 列数) }
}
