// 帯を横方向へ何枚に割るか。左端・中央・右端が頂点として存在する偶数にしておく。
const 横分割数 = 4

// 左端から右端まで、各列が中心線から測った符号付きの横距離。
function 列ごとの横距離を並べる(全幅メートル: number): number[] {
    const 横距離一覧: number[] = []
    for (let 列 = 0; 列 <= 横分割数; 列++) {
        横距離一覧.push(全幅メートル * (列 / 横分割数 - 0.5))
    }
    return 横距離一覧
}

// 道路スプラインの制御点列から帯状メッシュの頂点・UV・添字を生成する。
// 制御点が2つに満たず帯を張れないときはnullを返す(呼び出し元がメッシュを非表示にする)。
export function 道路帯幾何データを生成する(
    スプライン: 道路スプライン,
    全幅メートル: number,
    細分割数: number,
    高さ場モデル: 高さ場,
    Yオフセット: number,
): 道路帯幾何データ | null {
    if (スプライン.制御点列.length < 2) return null
    const 標本数 = 中心線の標本数を決める(スプライン.制御点列.length, 細分割数)
    const 標本列 = 中心線標本列を作る(スプライン, 標本数)
    const 点列 = 道路帯の列ごとの点列.標本列から組み立てる(標本列, 列ごとの横距離を並べる(全幅メートル))
    return 帯の格子を幾何データへ組み立てる(点列.列ごとの点列, 高さ場モデル, Yオフセット)
}
