import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 道路スプライン, 高さ場 } from '../../../編集モデル/index.ts'
import { 道路帯幾何データを生成する } from './道路帯ジオメトリ生成.ts'
import { 裏返った三角形の枚数を数える, 面積を持つ三角形があるか, 非数を含まないか } from './道路帯幾何データ検査.ts'

// 浮動小数点の丸めで面積の符号がぶれる範囲。1平方メートルの1万分の1未満は目に見えない。
const 面積の許容誤差 = 1e-4

function ヘアピンの道路を作る(全幅メートル: number): 道路スプライン {
    return new 道路スプライン({
        制御点列: [
            { x: 0, y: 0, z: -60 },
            { x: 0, y: 0, z: -20 },
            { x: 0, y: 0, z: 10 },
            { x: 2, y: 0, z: 14 },
            { x: 4, y: 0, z: 10 },
            { x: 4, y: 0, z: -20 },
            { x: 4, y: 0, z: -60 },
        ],
        全幅メートル,
        散布除外バッファメートル: 全幅メートル * 1.5,
        細分割数: 60,
    })
}

describe('道路帯ジオメトリ生成', () => {
    it('曲率半径より道半幅が大きいヘアピンでも三角形が裏返らず非数も出ないこと', () => {
        const 幾何 = 道路帯幾何データを生成する(ヘアピンの道路を作る(12), 12, 60, new 高さ場(33, 256), 0.06)
        assert.notStrictEqual(幾何, null)
        if (幾何 === null) return
        assert.strictEqual(裏返った三角形の枚数を数える(幾何, 面積の許容誤差), 0)
        assert.ok(面積を持つ三角形があるか(幾何, 面積の許容誤差), '面積を持つ三角形が1枚も無い')
        assert.ok(非数を含まないか(幾何), '頂点配列またはUV配列に非数がある')
    })

    it('直線区間では左右の端の間隔が指定した全幅と一致すること', () => {
        const 直線の道路 = new 道路スプライン({
            制御点列: [
                { x: 0, y: 0, z: -60 },
                { x: 0, y: 0, z: 0 },
                { x: 0, y: 0, z: 60 },
            ],
            全幅メートル: 10,
            散布除外バッファメートル: 15,
            細分割数: 40,
        })
        const 幾何 = 道路帯幾何データを生成する(直線の道路, 10, 40, new 高さ場(33, 256), 0)
        assert.notStrictEqual(幾何, null)
        if (幾何 === null) return

        const 一行の頂点数 = 5
        const 中央行 = Math.floor(幾何.頂点配列.length / 3 / 一行の頂点数 / 2)
        const 左端 = 中央行 * 一行の頂点数
        const 右端 = 左端 + 一行の頂点数 - 1
        const 幅 = Math.hypot(
            (幾何.頂点配列[右端 * 3] ?? 0) - (幾何.頂点配列[左端 * 3] ?? 0),
            (幾何.頂点配列[右端 * 3 + 2] ?? 0) - (幾何.頂点配列[左端 * 3 + 2] ?? 0),
        )
        assert.ok(Math.abs(幅 - 10) < 1e-3, `直線区間の全幅が一致しない: ${幅}`)
    })

    it('乱数で作った400本の道路のどれでも三角形が裏返らないこと', () => {
        const 高さ場モデル = new 高さ場(33, 512)
        let 種 = 12345
        const 乱数 = (): number => {
            種 = (種 * 1103515245 + 12345) & 0x7fffffff
            return 種 / 0x7fffffff
        }
        let 裏返り合計 = 0
        for (let 試行 = 0; 試行 < 400; 試行++) {
            const 制御点列 = []
            const 制御点数 = 2 + Math.floor(乱数() * 8)
            for (let 番号 = 0; 番号 < 制御点数; 番号++) {
                制御点列.push({ x: (乱数() - 0.5) * 120, y: (乱数() - 0.5) * 20, z: (乱数() - 0.5) * 120 })
            }
            const 全幅 = 2 + 乱数() * 22
            const 細分割数 = 20 + Math.floor(乱数() * 280)
            const 道路 = new 道路スプライン({ 制御点列, 全幅メートル: 全幅, 散布除外バッファメートル: 全幅 * 1.5, 細分割数 })
            const 幾何 = 道路帯幾何データを生成する(道路, 全幅, 細分割数, 高さ場モデル, 0.06)
            if (幾何 === null) continue
            assert.ok(非数を含まないか(幾何), `試行${試行}の幾何データに非数がある`)
            裏返り合計 += 裏返った三角形の枚数を数える(幾何, 面積の許容誤差)
        }
        assert.strictEqual(裏返り合計, 0)
    })
})
