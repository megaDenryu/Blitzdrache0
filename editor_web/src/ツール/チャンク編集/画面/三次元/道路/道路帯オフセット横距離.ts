import type { 中心線標本, 水平位置 } from './道路中心線標本列.ts'

function 内積(左: 水平位置, 右: 水平位置): number {
    return 左.x * 右.x + 左.z * 右.z
}

// 内側へ寄せた横距離が、今の横距離と中心線(距離0)の間からはみ出さないように丸める。
// 符号が反転すると帯の左右が入れ替わるため、反転も同時に禁じる。
function 中心線と今の距離の間へ収める(横距離: number, 今の横距離: number): number {
    if (今の横距離 >= 0) return Math.min(Math.max(横距離, 0), 今の横距離)
    return Math.max(Math.min(横距離, 0), 今の横距離)
}

// 前進量は「定数項 + 横距離 * 係数」の1次式になる。負になるなら0で止まる横距離まで中心線側へ寄せる。
// 定数項は中心線そのものの前進量であり、これが0以上である限り中心線(横距離0)は必ず条件を満たす。
// 定数項が負になるのは中心線自体が1標本の中で折り返した場合だけで、そのときはどの横距離でも
// 条件を満たせないため、前進量が最も大きくなる端を選ぶ。
function 前進の条件へ寄せる(今の横距離: number, 定数項: number, 係数: number): number {
    if (定数項 + 今の横距離 * 係数 >= 0) return 今の横距離
    if (定数項 < 0) return 今の横距離 * 係数 > 0 ? 今の横距離 : 0
    if (係数 === 0) return 0
    return 中心線と今の距離の間へ収める(-定数項 / 係数, 今の横距離)
}

// 中心線を横へ平行移動しただけの点は、曲率半径が横距離より小さい曲がりの内側で進行方向へ
// 後退し、点列が自分と交差して三角形が裏返る。三角形が表を向く条件は、隣り合う標本を結ぶ
// 前進の向きが、その2つの標本それぞれの進行方向に対して負にならないことである。
// 手前の区間から見た条件は今の標本の横距離を、次の区間から見た条件は同じく今の標本の横距離を
// 縛る(相手側の横距離は進行方向と直交するため前進量に効かない)。
// 引き戻し先を「直前の点の位置」にしないのは、直角を超える曲がりでは直前の点が曲がった先の
// 帯の内部に取り残され、留めを解いた瞬間に帯を横切る飛びが起きるためである。中心線側へ寄せると
// 内側の列は角で中心線へ集まってから反対側へ開き、帯を横切らずに済む。
export function 前進を保つ横距離を決める(
    標本: 中心線標本,
    直前の標本: 中心線標本 | undefined,
    次の標本: 中心線標本 | undefined,
    元の横距離: number,
): number {
    let 横距離 = 元の横距離
    if (直前の標本 !== undefined) {
        const 区間 = { x: 標本.中心位置.x - 直前の標本.中心位置.x, z: 標本.中心位置.z - 直前の標本.中心位置.z }
        横距離 = 前進の条件へ寄せる(横距離, 内積(区間, 直前の標本.進行方向), 内積(標本.横方向, 直前の標本.進行方向))
    }
    if (次の標本 !== undefined) {
        const 区間 = { x: 次の標本.中心位置.x - 標本.中心位置.x, z: 次の標本.中心位置.z - 標本.中心位置.z }
        横距離 = 前進の条件へ寄せる(横距離, 内積(区間, 次の標本.進行方向), -内積(標本.横方向, 次の標本.進行方向))
    }
    return 横距離
}

// 引き戻しの量は列ごとに独立して決まるため、角では内側の列より外側の列のほうが中心線へ
// 寄ってしまい、行の中で列の並び順が入れ替わることがある。順序が入れ替わった行は三角形が
// 裏返るため、横距離が列の順に単調非減少になるまで中心線側へ寄せ直す。
// 是正はいずれも横距離の大きさを小さくする向きにしか働かないため、前進の条件は保たれる。
export function 列の順に単調な横距離へ整える(横距離一覧: number[], 元の横距離一覧: readonly number[]): void {
    for (let 列 = 0; 列 + 1 < 横距離一覧.length; 列++) {
        const 手前 = 横距離一覧[列]
        const 次 = 横距離一覧[列 + 1]
        if ((元の横距離一覧[列 + 1] ?? 0) < 0 && 手前 !== undefined && 次 !== undefined && 次 < 手前) {
            横距離一覧[列 + 1] = 手前
        }
    }
    for (let 列 = 横距離一覧.length - 1; 列 > 0; 列--) {
        const 手前 = 横距離一覧[列 - 1]
        const 次 = 横距離一覧[列]
        if ((元の横距離一覧[列 - 1] ?? 0) > 0 && 手前 !== undefined && 次 !== undefined && 手前 > 次) {
            横距離一覧[列 - 1] = 次
        }
    }
}
