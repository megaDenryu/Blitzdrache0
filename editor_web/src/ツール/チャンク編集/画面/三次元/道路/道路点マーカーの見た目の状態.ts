import { 同じ道路点を指すか, type 道路点の在り処 } from '../../../編集モデル/index.ts'
import type { 道路点マーカーの状態 } from './道路点マーカー材質束.ts'

// 道路点マーカーの表示の指定とは、いまどの点をつかんでいて、どの点を選んでいて、どの道が
// アクティブかをまとめたもののことである。同期サービスがこの1つを渡し、マーカーの一覧が
// 点ごとの見た目の状態へほどく。
export interface 道路点マーカーの表示の指定 {
    readonly 選択中の道路点: 道路点の在り処 | null
    readonly つかんでいる道路点: 道路点の在り処 | null
    readonly アクティブな道路の添字: number | null
}

// つかんでいる点がいちばん強く、次に選んでいる点、次にアクティブな道の点、それ以外が通常である。
export function 道路点の見た目の状態を決める(
    在り処: 道路点の在り処,
    指定: 道路点マーカーの表示の指定,
): 道路点マーカーの状態 {
    if (同じ道路点を指すか(在り処, 指定.つかんでいる道路点)) return 'つかんでいる'
    if (同じ道路点を指すか(在り処, 指定.選択中の道路点)) return '選択中'
    if (在り処.道路添字 === 指定.アクティブな道路の添字) return 'アクティブな道の点'
    return '通常'
}
