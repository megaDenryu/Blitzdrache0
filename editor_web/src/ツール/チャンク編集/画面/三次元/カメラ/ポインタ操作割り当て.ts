export type ポインタ操作種別 = 'カメラ回転' | 'カメラ平行移動' | '主作業'

// 統一操作規則(全モード共通): 右ドラッグ=カメラ回転、中ドラッグ=カメラ平行移動、
// 左ドラッグ=カメラモードならカメラ回転・それ以外はそのモードの主作業。
// ホイールのズームはこの関数の対象外であり呼び出し元が常時処理する。
export function ポインタ操作の割り当てを決める(
    ボタン: number,
    カメラモードか: boolean,
): ポインタ操作種別 {
    if (ボタン === 2) return 'カメラ回転'
    if (ボタン === 1) return 'カメラ平行移動'
    if (ボタン === 0 && カメラモードか) return 'カメラ回転'
    return '主作業'
}
