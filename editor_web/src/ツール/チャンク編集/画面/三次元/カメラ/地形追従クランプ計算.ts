// 地形追従カメラ制御器から呼ばれる純関数。地形の高さのサンプル値(既にサンプリング済みの数値)
// だけを受け取り、注視点の新しい高さと、次回の昇降するの基準にする「地形からの相対高さ」を計算する。
// 高さ場やThree.jsに依存しないため、DOM無しで単体テストできる。
export interface 地形追従クランプ入力 {
    // 現在保持している「地形からの相対高さ」(E/Qの昇降するで積み上げてきた値)
    readonly 地形上の相対高さ: number
    // 注視点の直下(x,z)における地形のサンプル高さ
    readonly 注視点地形高さ: number
    // カメラの直下(x,z)における地形のサンプル高さ
    readonly カメラ地形高さ: number
    // 現在のカメラ高さ - 現在の注視点高さ(軌道半径*cos(垂直角)に相当。水平角・垂直角・距離が
    // 今回の操作で変わらない前提のもとでは、注視点の高さを動かすとカメラの高さも同じ量だけ動く)
    readonly カメラ垂直オフセット: number
    // カメラの下限クリアランス(地形からの最低高さ、メートル)
    readonly 最低クリアランスメートル: number
}

export interface 地形追従クランプ結果 {
    // 反映すべき注視点の新しい高さ
    readonly 新注視点高さ: number
    // 次回の昇降するの基準にする「地形からの相対高さ」(フロアクランプが働いた場合は
    // 実際に反映された高さへ合わせて更新される)
    readonly 新相対高さ: number
}

// 注視点の高さを「地形の高さ + 地形上の相対高さ」へ合わせ、その結果のカメラ高さが
// 床(地形の高さ + 最低クリアランス)を割るなら、注視点を必要な分だけ押し上げて
// カメラが地形へめり込まないようにする。
export function 地形追従クランプを計算する(入力: 地形追従クランプ入力): 地形追従クランプ結果 {
    const 素の注視点高さ = 入力.注視点地形高さ + 入力.地形上の相対高さ
    const 素のカメラ高さ = 素の注視点高さ + 入力.カメラ垂直オフセット
    const 床の高さ = 入力.カメラ地形高さ + 入力.最低クリアランスメートル

    if (素のカメラ高さ >= 床の高さ) {
        return { 新注視点高さ: 素の注視点高さ, 新相対高さ: 入力.地形上の相対高さ }
    }

    const 押し上げ量 = 床の高さ - 素のカメラ高さ
    const 新注視点高さ = 素の注視点高さ + 押し上げ量
    return { 新注視点高さ, 新相対高さ: 新注視点高さ - 入力.注視点地形高さ }
}
