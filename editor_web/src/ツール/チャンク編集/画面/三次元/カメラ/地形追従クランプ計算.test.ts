import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 地形追従クランプを計算する } from './地形追従クランプ計算.ts'

describe('地形追従クランプ計算', () => {
    it('床を割らないときは注視点の高さを地形+相対高さへそのまま合わせ、相対高さは変えないこと', () => {
        const 結果 = 地形追従クランプを計算する({
            地形上の相対高さ: 3,
            注視点地形高さ: 10,
            カメラ地形高さ: 8,
            カメラ垂直オフセット: 50,
            最低クリアランスメートル: 2,
        })

        assert.strictEqual(結果.新注視点高さ, 13)
        assert.strictEqual(結果.新相対高さ, 3)
    })

    it('カメラが床を割るときは注視点を押し上げてカメラの高さを床ちょうどへ戻すこと', () => {
        const 結果 = 地形追従クランプを計算する({
            地形上の相対高さ: 0,
            注視点地形高さ: 10,
            カメラ地形高さ: 10,
            カメラ垂直オフセット: 1,
            最低クリアランスメートル: 2,
        })

        // 素のカメラ高さ = 10 + 1 = 11、床 = 10 + 2 = 12 なので1押し上げが必要
        assert.strictEqual(結果.新注視点高さ, 11)
        assert.strictEqual(結果.新相対高さ, 1)
    })

    it('ちょうど床の高さのときは押し上げが発生しないこと(境界値)', () => {
        const 結果 = 地形追従クランプを計算する({
            地形上の相対高さ: 0,
            注視点地形高さ: 0,
            カメラ地形高さ: 0,
            カメラ垂直オフセット: 2,
            最低クリアランスメートル: 2,
        })

        assert.strictEqual(結果.新注視点高さ, 0)
        assert.strictEqual(結果.新相対高さ, 0)
    })

    it('カメラ側の地形が注視点側より高い崖でも、カメラ基準の床でクランプされること', () => {
        const 結果 = 地形追従クランプを計算する({
            地形上の相対高さ: 0,
            注視点地形高さ: 0,
            カメラ地形高さ: 20,
            カメラ垂直オフセット: 5,
            最低クリアランスメートル: 2,
        })

        // 素のカメラ高さ = 0 + 5 = 5、床 = 20 + 2 = 22 なので17押し上げが必要
        assert.strictEqual(結果.新注視点高さ, 17)
        assert.strictEqual(結果.新相対高さ, 17)
    })
})
