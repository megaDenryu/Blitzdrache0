import type { 位置3次元 } from '../../../../../生成/編集資源契約.ts'
import type { 高さ場 } from '../../../編集モデル/index.ts'
import { 軌道カメラ制御器 } from '../../../../../三次元の視点操作/軌道カメラ制御器.ts'
import { 地形追従クランプを計算する } from './地形追従クランプ計算.ts'

const 既定最低クリアランスメートル = 2

// 軌道カメラ制御器を包み、トグルが有効なとき回転・パン・WASDQEの後に注視点とカメラの高さを
// 地形へ追従させる(既定オフ)。無効時は軌道カメラ制御器の挙動をそのまま素通しする。
// 有効時はE/Qの昇降するの意味が「絶対高さの上下」から「地形からの相対高さの上下」へ変わる。
export class 地形追従カメラ制御器 {
    private _有効か: boolean = false
    private _地形からの相対高さ: number = 0

    public constructor(
        private readonly _カメラ制御: 軌道カメラ制御器,
        private readonly _地形高さ場: 高さ場,
        private readonly _最低クリアランスメートル: number = 既定最低クリアランスメートル,
    ) {}

    // オンにする瞬間、地形からの相対高さを0へ戻す(=注視点を地形の表面へ乗せる)。
    // オンにした操作が視覚的に分かるようにするため、直前の高さをそのまま引き継がない。
    public 地形追従を設定する(有効: boolean): void {
        const 新規にオンにするか = 有効 && !this._有効か
        this._有効か = 有効
        if (新規にオンにするか) {
            this._地形からの相対高さ = 0
            this._地形へ追従する()
        }
    }

    public 有効か(): boolean {
        return this._有効か
    }

    public 回転する(デルタX: number, デルタY: number): void {
        this._カメラ制御.回転する(デルタX, デルタY)
        this._地形へ追従する()
    }

    public 移動する(デルタX: number, デルタY: number): void {
        this._カメラ制御.移動する(デルタX, デルタY)
        this._地形へ追従する()
    }

    public 昇降する(デルタ: number): void {
        if (!this._有効か) {
            this._カメラ制御.昇降する(デルタ)
            return
        }
        const 係数 = this._カメラ制御.距離を取得する() * 0.002
        this._地形からの相対高さ += デルタ * 係数
        this._地形へ追従する()
    }

    // ズームは注視点を動かさないため地形追従の対象外にする(仕様上の対象はWASDQE移動と回転・パンのみ)。
    public 拡大縮小する(デルタY: number): void {
        this._カメラ制御.拡大縮小する(デルタY)
    }

    public 注視点を取得する(): 位置3次元 {
        return this._カメラ制御.注視点を取得する()
    }

    private _地形へ追従する(): void {
        if (!this._有効か) return

        const 注視点 = this._カメラ制御.注視点を取得する()
        const カメラ位置 = this._カメラ制御.カメラ位置を取得する()
        const 結果 = 地形追従クランプを計算する({
            地形上の相対高さ: this._地形からの相対高さ,
            注視点地形高さ: this._地形高さ場.標本高さを取得する(注視点.x, 注視点.z),
            カメラ地形高さ: this._地形高さ場.標本高さを取得する(カメラ位置.x, カメラ位置.z),
            カメラ垂直オフセット: カメラ位置.y - 注視点.y,
            最低クリアランスメートル: this._最低クリアランスメートル,
        })

        this._地形からの相対高さ = 結果.新相対高さ
        this._カメラ制御.注視点の高さを設定する(結果.新注視点高さ)
    }
}
