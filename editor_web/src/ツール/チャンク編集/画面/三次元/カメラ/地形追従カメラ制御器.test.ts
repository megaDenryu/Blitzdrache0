import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 軌道カメラ制御器 } from '../../../../../三次元の視点操作/軌道カメラ制御器.ts'
import { 地形追従カメラ制御器 } from './地形追従カメラ制御器.ts'
import { 高さ場 } from '../../../編集モデル/高さ場.ts'

// 透視カメラの位置反映だけを記録する偽物(軌道カメラ制御器.test.tsと同じもの)。
class 位置記録カメラ {
    位置履歴: { x: number; y: number; z: number }[] = []

    位置を設定する(x: number, y: number, z: number): this {
        this.位置履歴.push({ x, y, z })
        return this
    }

    注視点を設定する(): this {
        return this
    }
}

function 一定高さの高さ場を作る(高さ: number) {
    const 解像度 = 4
    const 格子データ = new Float32Array(解像度 * 解像度).fill(高さ)
    return new 高さ場(解像度, 100, 格子データ)
}

describe('地形追従カメラ制御器', () => {
    it('既定オフでは昇降するが軌道カメラ制御器の絶対高さ操作をそのまま素通しすること', () => {
        const カメラ = new 位置記録カメラ()
        const 軌道 = new 軌道カメラ制御器(カメラ, 100, 10, 1000)
        const 地形 = new 地形追従カメラ制御器(軌道, 一定高さの高さ場を作る(0))

        assert.strictEqual(地形.有効か(), false)
        const 昇降前 = 軌道.注視点を取得する().y
        地形.昇降する(10)
        assert.ok(軌道.注視点を取得する().y > 昇降前)
    })

    it('有効化すると回転する呼び出し後に注視点の高さが地形の高さへ合うこと', () => {
        const カメラ = new 位置記録カメラ()
        const 軌道 = new 軌道カメラ制御器(カメラ, 100, 10, 1000)
        const 地形 = new 地形追従カメラ制御器(軌道, 一定高さの高さ場を作る(5))

        地形.地形追従を設定する(true)
        地形.回転する(0, 0)

        assert.strictEqual(軌道.注視点を取得する().y, 5)
    })

    it('有効時の昇降するは絶対高さでなく地形からの相対高さを積み増すこと', () => {
        const カメラ = new 位置記録カメラ()
        const 軌道 = new 軌道カメラ制御器(カメラ, 100, 10, 1000)
        const 地形 = new 地形追従カメラ制御器(軌道, 一定高さの高さ場を作る(5))

        地形.地形追従を設定する(true)
        地形.回転する(0, 0)
        const 昇降前 = 軌道.注視点を取得する().y
        地形.昇降する(10)
        const 昇降後 = 軌道.注視点を取得する().y

        assert.ok(昇降後 > 昇降前, `Eの後は地形+相対高さの分だけ高くなるべき(前:${昇降前}, 後:${昇降後})`)
    })

    it('有効時はカメラの高さが地形+最低クリアランスを下回らないようクランプされること', () => {
        const カメラ = new 位置記録カメラ()
        // 最小距離を小さくして、水平近く(垂直角を最大まで倒す)にすればカメラ高さが
        // 注視点高さへ近づき、地形に対してクリアランス割れを起こしやすくなる。
        const 軌道 = new 軌道カメラ制御器(カメラ, 15, 10, 1000)
        const 地形 = new 地形追従カメラ制御器(軌道, 一定高さの高さ場を作る(0), 2)

        地形.地形追従を設定する(true)
        // 垂直角を最大近く(水平に近い見下ろし)へ倒し、カメラ垂直オフセットを小さくする
        地形.回転する(0, -400)

        const カメラ高さ = 軌道.カメラ位置を取得する().y
        assert.ok(カメラ高さ >= 2 - 1e-9, `カメラ高さは床(地形0+クリアランス2)を下回らないべき: ${カメラ高さ}`)
    })
})
