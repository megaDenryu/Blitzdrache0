// タブを開いた直後のモード。操作帯のボタン・棚の案内・編集状態の3つが同じ値から始まるように、
// 綴りをここ1箇所へ閉じる(エディター制作スキル第2条)。
export const 初期の編集モード: 編集モード = '選択'

// 道路点マーカーを画面に出すモード。他のモードでは触れない物体が浮いて見えるため隠す。
export function 道路の点を扱うモードか(モード: 編集モード): boolean {
    return モード === '道作成' || モード === '道編集'
}

// 見下ろし図の上で編集するモード。三次元の表示中にこのモードを選んだら表示面を見下ろし図へ移す。
// 逆に見下ろし図の表示中に三次元のモードを選んでも表示面は変えない(視点のためにモードを押させない)。
// 参照: `_doc/設計/見下ろし図による地形編集.md`「判断7」、`_doc/設計/ゲーム開発用エディター基盤.md`「判断13」
export function 見下ろし図で編集するモードか(モード: 編集モード): boolean {
    return モード === '等高線' || モード === '大升'
}

