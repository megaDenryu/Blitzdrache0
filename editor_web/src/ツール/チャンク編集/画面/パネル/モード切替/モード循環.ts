export type 循環方向 = 1 | -1

// モード一覧内で現在モードの次(方向=1)・前(方向=-1)のモードを返す。
// 現在モードが一覧に無いときは先頭を基準にする(型では起こり得ないが、
// 外部から渡された値が一覧に無い場合の安全な既定として先頭へ寄せる)。
export function モードを循環させる<Tモード>(
    モード一覧: readonly Tモード[],
    現在モード: Tモード,
    方向: 循環方向,
): Tモード {
    if (モード一覧.length === 0) {
        throw new Error('モード一覧が空です')
    }
    const 現在添字 = モード一覧.indexOf(現在モード)
    const 基準添字 = 現在添字 === -1 ? 0 : 現在添字
    const 次添字 = (基準添字 + 方向 + モード一覧.length) % モード一覧.length
    return モード一覧[次添字]
}
