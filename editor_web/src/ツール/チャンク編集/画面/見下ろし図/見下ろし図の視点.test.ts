import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 見下ろし図の視点 } from './見下ろし図の視点.ts'

function ほぼ等しい(実際: number, 期待: number, 文言: string): void {
    assert.ok(Math.abs(実際 - 期待) < 1e-9, `${文言}: 期待=${期待}, 実際=${実際}`)
}

describe('見下ろし図の視点', () => {
    it('チャンク全体が収まる初期視点はチャンク中心を枠の中央に置き、一辺が短辺の9割になること', () => {
        const 視点 = 見下ろし図の視点.チャンク全体が収まる視点を作る(256, 800, 600)
        const 中心 = 視点.ワールドから画素へ({ x: 0, z: 0 })
        ほぼ等しい(中心.x, 400, '中心x')
        ほぼ等しい(中心.y, 300, '中心y')
        const 北西 = 視点.ワールドから画素へ({ x: -128, z: -128 })
        const 南東 = 視点.ワールドから画素へ({ x: 128, z: 128 })
        ほぼ等しい(南東.x - 北西.x, 540, '一辺の画素幅')
        assert.ok(北西.y < 南東.y, '北(-Z)が画面の上に来るべき')
    })

    it('ワールドと画素の変換が往復で元に戻ること', () => {
        const 視点 = 見下ろし図の視点.生成する(2.5, { x: 37, y: 91 })
        const 元 = { x: -12.5, z: 40.25 }
        const 戻り = 視点.画素からワールドへ(視点.ワールドから画素へ(元))
        ほぼ等しい(戻り.x, 元.x, 'x')
        ほぼ等しい(戻り.z, 元.z, 'z')
    })

    it('カーソルを中心にズームするとカーソルの下のワールドの点が動かないこと', () => {
        const 視点 = 見下ろし図の視点.生成する(2, { x: 100, y: 100 })
        const カーソル = { x: 250, y: 130 }
        const 前 = 視点.画素からワールドへ(カーソル)
        const 後の視点 = 視点.カーソルを中心にズームする(カーソル, 1.5)
        const 後 = 後の視点.画素からワールドへ(カーソル)
        ほぼ等しい(後の視点.画素毎メートル, 3, '倍率')
        ほぼ等しい(後.x, 前.x, 'x')
        ほぼ等しい(後.z, 前.z, 'z')
    })

    it('倍率が上限で止まるときもカーソルの下の点が動かないこと', () => {
        const 視点 = 見下ろし図の視点.生成する(150, { x: 0, y: 0 })
        const カーソル = { x: 300, y: 300 }
        const 前 = 視点.画素からワールドへ(カーソル)
        const 後の視点 = 視点.カーソルを中心にズームする(カーソル, 10)
        ほぼ等しい(後の視点.画素毎メートル, 200, '倍率は上限で止まる')
        const 後 = 後の視点.画素からワールドへ(カーソル)
        ほぼ等しい(後.x, 前.x, 'x')
        ほぼ等しい(後.z, 前.z, 'z')
    })

    it('画素で平行移動すると同じワールドの点が移動量だけずれた画素に写ること', () => {
        const 視点 = 見下ろし図の視点.生成する(4, { x: 10, y: 20 })
        const 後 = 視点.画素で平行移動する(15, -5)
        const 点 = { x: 3, z: 7 }
        const 前の画素 = 視点.ワールドから画素へ(点)
        const 後の画素 = 後.ワールドから画素へ(点)
        ほぼ等しい(後の画素.x - 前の画素.x, 15, 'x')
        ほぼ等しい(後の画素.y - 前の画素.y, -5, 'y')
    })
})
