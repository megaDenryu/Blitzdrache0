import type { 高さ場, 地表材質 } from '../../編集モデル/index.ts'
import { 高さの範囲を求める } from '../三次元/地形/地形頂点計算.ts'
import { RGBを混ぜる, 十六進の色文字列をRGBへ, 標高グラデーションの色, type RGB, type 下地の配色 } from './下地の配色.ts'

// 見下ろし図の下地の画像。格子1点を1画素に写し、幅と高さはどちらも格子の解像度である。
// 画素の並びは高さ場の格子データと同じ(添字 = z * 解像度 + x)で、zが0の行が先頭にある。
// 見下ろし図は画面の上に北(ワールドの-Z)を置くため、先頭の行がそのまま画像の上端になり行の反転は要らない。
// ブラウザの ImageData へ包むのは描く側の仕事にし、この計算はNodeのテストから呼べるようにしておく。
export interface 下地の画像 {
    readonly 幅: number
    readonly 高さ: number
    readonly 画素: Uint8ClampedArray<ArrayBuffer>
}

// 材質の識別色に標高の色を混ぜる割合。三次元は識別色を陰影で暗くして起伏を見せるが、見下ろし図に陰影は無いため
// 標高の色で起伏を読ませる。識別色が読めなくなる手前の値として半分より少し弱くする。
const 標高の色を混ぜる割合 = 0.4

export function 下地の画像を作る(高さ場モデル: 高さ場, 地表材質モデル: 地表材質, 配色: 下地の配色): 下地の画像 {
    const 解像度 = 高さ場モデル.解像度
    if (地表材質モデル.解像度 !== 解像度) {
        throw new Error(`高さ場と地表材質の解像度が違う: 高さ場=${解像度}, 地表材質=${地表材質モデル.解像度}`)
    }
    const 材質色 = [
        十六進の色文字列をRGBへ(配色.材質色.草),
        十六進の色文字列をRGBへ(配色.材質色.泥),
        十六進の色文字列をRGBへ(配色.材質色.岩),
        十六進の色文字列をRGBへ(配色.材質色.砂),
    ]
    const 範囲 = 高さの範囲を求める(高さ場モデル.格子データ)
    const 高さの幅 = Math.max(範囲.最大 - 範囲.最小, 0.001)
    const 画素 = new Uint8ClampedArray(解像度 * 解像度 * 4)
    for (let 添字 = 0; 添字 < 解像度 * 解像度; 添字++) {
        const 識別色 = 材質の重みで混ぜた色(地表材質モデル.材質データ, 添字, 材質色)
        const 標高 = 高さ場モデル.格子データ[添字] ?? 範囲.最小
        const 標高色 = 標高グラデーションの色(配色, (標高 - 範囲.最小) / 高さの幅)
        const 色 = RGBを混ぜる(識別色, 標高色, 標高の色を混ぜる割合)
        画素[添字 * 4 + 0] = 色.r
        画素[添字 * 4 + 1] = 色.g
        画素[添字 * 4 + 2] = 色.b
        画素[添字 * 4 + 3] = 255
    }
    return { 幅: 解像度, 高さ: 解像度, 画素 }
}

// 三次元の地形シェーダーと同じく4層の重みを合計で正規化して識別色を混ぜる。合計が0の画素は草にする。
function 材質の重みで混ぜた色(材質データ: Uint8Array, 添字: number, 材質色: readonly RGB[]): RGB {
    let 合計 = 0
    for (let 層 = 0; 層 < 4; 層++) 合計 += 材質データ[添字 * 4 + 層] ?? 0
    if (合計 === 0) return 材質色[0] ?? { r: 0, g: 0, b: 0 }
    let r = 0
    let g = 0
    let b = 0
    for (let 層 = 0; 層 < 4; 層++) {
        const 重み = (材質データ[添字 * 4 + 層] ?? 0) / 合計
        const 色 = 材質色[層] ?? { r: 0, g: 0, b: 0 }
        r += 色.r * 重み
        g += 色.g * 重み
        b += 色.b * 重み
    }
    return { r, g, b }
}
