// 見下ろし図の上でのワールドXZ(チャンク中心が原点・メートル)とキャンバスの画素(CSS画素・左上が原点)の
// 相互変換を持つ視点。見下ろし図は画面の上に北(ワールドの-Z)を置くため、Zが増えると画素のyも増える。
// 値は不変であり、ズームや平行移動は新しい視点を返す。回転は無い(設計正本の判断6)。
// 参照: `_doc/設計/見下ろし図による地形編集.md`「判断6」

export interface ワールドXZ {
    readonly x: number
    readonly z: number
}

export interface 画素位置 {
    readonly x: number
    readonly y: number
}

// 1メートルあたりの画素数の下限と上限。下限はチャンク1辺(256m)が数十画素へ潰れる手前、
// 上限は格子1点(2m)が数百画素へ広がる手前で止める。
const 倍率の下限 = 0.1
const 倍率の上限 = 200

// チャンクの全体を初期の視点で収めるとき、枠の短辺のうち下地に使う割合。
const 初期表示の余白を除いた割合 = 0.9

export class 見下ろし図の視点 {
    private constructor(
        public readonly 画素毎メートル: number,
        public readonly 原点の画素: 画素位置,
    ) {}

    public static 生成する(画素毎メートル: number, 原点の画素: 画素位置): 見下ろし図の視点 {
        return new 見下ろし図の視点(Math.min(倍率の上限, Math.max(倍率の下限, 画素毎メートル)), 原点の画素)
    }

    // 一辺のチャンクが枠の中央に収まる視点を作る。枠が0以下のときは倍率の下限で中央に置く。
    public static チャンク全体が収まる視点を作る(一辺のメートル: number, 枠の幅: number, 枠の高さ: number): 見下ろし図の視点 {
        const 短辺 = Math.min(枠の幅, 枠の高さ)
        const 倍率 = 短辺 > 0 ? (短辺 * 初期表示の余白を除いた割合) / 一辺のメートル : 倍率の下限
        return 見下ろし図の視点.生成する(倍率, { x: 枠の幅 / 2, y: 枠の高さ / 2 })
    }

    public ワールドから画素へ(位置: ワールドXZ): 画素位置 {
        return {
            x: this.原点の画素.x + 位置.x * this.画素毎メートル,
            y: this.原点の画素.y + 位置.z * this.画素毎メートル,
        }
    }

    public 画素からワールドへ(画素: 画素位置): ワールドXZ {
        return {
            x: (画素.x - this.原点の画素.x) / this.画素毎メートル,
            z: (画素.y - this.原点の画素.y) / this.画素毎メートル,
        }
    }

    // カーソルの下にあるワールドの点が動かないように倍率を掛ける。倍率が上限・下限で止まったときも
    // その点は動かない。
    public カーソルを中心にズームする(カーソルの画素: 画素位置, 係数: number): 見下ろし図の視点 {
        const 新しい倍率 = Math.min(倍率の上限, Math.max(倍率の下限, this.画素毎メートル * 係数))
        const 実際の係数 = 新しい倍率 / this.画素毎メートル
        return new 見下ろし図の視点(新しい倍率, {
            x: カーソルの画素.x - (カーソルの画素.x - this.原点の画素.x) * 実際の係数,
            y: カーソルの画素.y - (カーソルの画素.y - this.原点の画素.y) * 実際の係数,
        })
    }

    public 画素で平行移動する(移動量x: number, 移動量y: number): 見下ろし図の視点 {
        return new 見下ろし図の視点(this.画素毎メートル, {
            x: this.原点の画素.x + 移動量x,
            y: this.原点の画素.y + 移動量y,
        })
    }
}
