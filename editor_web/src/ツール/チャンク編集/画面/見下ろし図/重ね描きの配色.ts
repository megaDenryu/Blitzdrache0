// 下地の上に重ねる等高線と粗マスの線・文字の色と太さ。下地は標高と識別色で埋まっているため、
// 重ねる線は明暗の差で読めるよう白系と、選択を示す1色だけにする。
// 材質の識別色は下地と同じくマテリアル台帳の値を受け取り、ここには書かない。
export const 重ね描きの配色 = {
    等高線: 'rgba(255, 255, 255, 0.85)',
    選択中の等高線: 'rgba(255, 200, 60, 1)',
    描いている途中の等高線: 'rgba(120, 220, 255, 0.95)',
    等高線の頂点の縁: 'rgba(0, 0, 0, 0.6)',
    高さの文字: 'rgba(255, 255, 255, 0.95)',
    高さの文字の縁: 'rgba(0, 0, 0, 0.8)',
    粗マスの格子線: 'rgba(255, 255, 255, 0.25)',
    粗マスの塗りの縁: 'rgba(255, 255, 255, 0.7)',
    選択中の粗マスの枠: 'rgba(255, 200, 60, 1)',
} as const

export const 重ね描きの寸法 = {
    等高線の太さ画素: 2,
    頂点の半径画素: 4,
    破線の刻み画素: 6,
    文字の大きさ画素: 11,
    粗マスの格子線の太さ画素: 1,
    粗マスの塗りの不透明度: 0.45,
    高さの文字を描く升の幅の割合: 0.9,
    選択中の粗マスの枠の太さ画素: 3,
} as const

// 頂点・線分をつかむときの当たりの半径(画素)。頂点の丸より少し広くして狙いやすくする。
export const 当たりの半径画素 = 6

const 高さの文字のフォント = `${重ね描きの寸法.文字の大きさ画素}px sans-serif`

export function 高さの文字を描く(文脈: CanvasRenderingContext2D, 文: string, x: number, y: number): void {
    文脈.font = 高さの文字のフォント
    文脈.textBaseline = 'middle'
    文脈.textAlign = 'center'
    文脈.lineWidth = 3
    文脈.strokeStyle = 重ね描きの配色.高さの文字の縁
    文脈.strokeText(文, x, y)
    文脈.fillStyle = 重ね描きの配色.高さの文字
    文脈.fillText(文, x, y)
}

// 文が最大幅画素に収まるかを判定する。粗マスの高さの数字は、ズームが小さく粗マスの描画幅が狭いときに
// 文字だけが升からはみ出して読みにくくなるため、描く前にここで確かめる。
export function 高さの文字が収まるか(文脈: CanvasRenderingContext2D, 文: string, 最大幅画素: number): boolean {
    文脈.font = 高さの文字のフォント
    return 文脈.measureText(文).width <= 最大幅画素
}
