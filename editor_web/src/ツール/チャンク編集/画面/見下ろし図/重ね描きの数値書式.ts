// 見下ろし図に描く高さの数字の書式化。高さ場から大升を生成すると小数点が大量に並んで見にくいという
// オーナー判定への対処であり、等高線と大升のどちらの重ね描きもこの関数だけを通す。

// 高さメートルを見下ろし図へ描く文字にする。小数第1位で丸め、絶対値が100以上のときは整数にする。
// 0未満で丸めた結果が0になる値は「-0.0」ではなく「0.0」で返す。
export function 高さを図の文字にする(高さメートル: number): string {
    if (Math.abs(高さメートル) >= 100) return Math.round(高さメートル).toString()
    const 丸めた文字 = 高さメートル.toFixed(1)
    return 丸めた文字 === '-0.0' ? '0.0' : 丸めた文字
}
