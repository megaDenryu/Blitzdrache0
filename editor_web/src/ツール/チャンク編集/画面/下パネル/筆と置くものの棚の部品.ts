import { 造成パネル } from '../パネル/造成/造成パネル.ts'
import { 地表ペイントパネル } from '../パネル/地表ペイント/地表ペイントパネル.ts'
import { 道を引き始めるパネル } from '../パネル/共通/道を引き始めるパネル.ts'
import type { 編集モード } from '../パネル/モード切替/モード定義.ts'
import { モードの案内札 } from './モードの案内札.ts'
import { 地表の材質の筆の初期値, 造成の筆の初期値 } from './筆の初期値.ts'
import { 置ける建物の棚 } from './置ける建物の棚.ts'

// 筆と置くものの棚が集約する部品の型契約(部品DTO)。ここに並ぶのはすべて「これから使うもの」であり、
// 選んでいるものへの設定は右サイドバーのインスペクターが持つ(設計正本の判断14)。
export class 筆と置くものの棚の部品 {
    private constructor(
        public readonly 案内: モードの案内札,
        public readonly 地形の筆: 造成パネル,
        public readonly 地表の材質: 地表ペイントパネル,
        public readonly 置ける建物: 置ける建物の棚,
        public readonly 道を引き始める: 道を引き始めるパネル,
    ) {}

    // 筆の初期値は編集状態と同じ1箇所から取る。人が触る前の棚の表示と、実際に筆が使う値が
    // ずれていると、表示が正本と一致しない(判断6)。
    public static 作る(初期モード: 編集モード): 筆と置くものの棚の部品 {
        return new 筆と置くものの棚の部品(
            new モードの案内札(初期モード),
            new 造成パネル(造成の筆の初期値.種別, 造成の筆の初期値.半径メートル, 造成の筆の初期値.強さ),
            new 地表ペイントパネル(地表の材質の筆の初期値.層, 地表の材質の筆の初期値.半径メートル, 地表の材質の筆の初期値.流量),
            new 置ける建物の棚(),
            new 道を引き始めるパネル(),
        )
    }

    public delete(): void {
        this.案内.delete()
        this.地形の筆.delete()
        this.地表の材質.delete()
        this.置ける建物.delete()
        this.道を引き始める.delete()
    }
}
