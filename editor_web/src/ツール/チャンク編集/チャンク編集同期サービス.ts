import type { ワールド編集状態, 道路の一覧 } from './編集モデル/index.ts'
import type { チャンク編集画面部品 } from './画面/index.ts'
import type { チャンク編集状態 } from './チャンク編集状態.ts'
import { 道路の点を扱うモードか } from './画面/パネル/モード切替/モード定義.ts'
import { 居なくなった道路と道路点の選択を外す } from './選択中の道路点の後始末.ts'
import { 見下ろし図のパネルを同期する } from './見下ろし図のパネルを同期する.ts'

// 編集モデルの状態変化を三次元描画部品および3つの区画(エディタ領域の操作帯・下パネルの棚・
// 右サイドバーのインスペクター)へ一括同期する。
export class チャンク編集同期サービス {
    public constructor(
        private readonly _モデル: ワールド編集状態,
        private readonly _UI状態: チャンク編集状態,
        private readonly _部品: チャンク編集画面部品,
    ) {}

    public 全体を同期する(): void {
        this.地形を同期する()
        this.道路を同期する()
        this.建物を同期する()
        this.散布を同期する()
        this.UIを同期する()
    }

    public 地形を同期する(): void {
        const チャンク = this._モデル.チャンクを取得する(this._UI状態.対象チャンク座標)
        this._部品.三次元ビュー.地形.高さ場を更新する(チャンク.高さ場)
        this._部品.三次元ビュー.地形.地表材質を更新する()
        this._部品.見下ろし図.地形を受け取る(チャンク.高さ場, チャンク.地表材質)
    }

    public 道路を同期する(): void {
        const チャンク = this._モデル.チャンクを取得する(this._UI状態.対象チャンク座標)
        居なくなった道路と道路点の選択を外す(this._UI状態, チャンク.道路一覧)
        this._部品.三次元ビュー.道路帯.更新する(チャンク.道路一覧, チャンク.高さ場)
        this._部品.三次元ビュー.道路点マーカー.更新する(チャンク.道路一覧, {
            選択中の道路点: this._UI状態.選択中の道路点,
            つかんでいる道路点: this._UI状態.つかんでいる道路点,
            アクティブな道路の添字: this._UI状態.アクティブな道路の添字,
        })
    }

    public 建物を同期する(): void {
        const チャンク = this._モデル.チャンクを取得する(this._UI状態.対象チャンク座標)
        this._部品.三次元ビュー.建物.更新する(チャンク.建物)
        this._部品.インスペクター.部品.建物.件数を更新する(チャンク.建物.一覧を取得する().length)
        this._部品.棚.部品.置ける建物.未解決の建物定義を表示する(
            this._部品.三次元ビュー.建物.未解決の建物定義ID一覧を取得する(),
        )
    }

    public 散布を同期する(): void {
        const チャンク = this._モデル.チャンクを取得する(this._UI状態.対象チャンク座標)
        const 個体一覧 = チャンク.散布の個体一覧を導く()
        this._部品.三次元ビュー.散布.散布の個体を更新する(個体一覧, チャンク.高さ場)
        this._部品.インスペクター.部品.散布.本数を更新する(個体一覧.length)
    }

    public UIを同期する(): void {
        const チャンク = this._モデル.チャンクを取得する(this._UI状態.対象チャンク座標)
        this._部品.三次元ビュー.道路点マーカー.表示するか設定する(道路の点を扱うモードか(this._UI状態.モード))
        this._部品.操作帯.表示を更新する(this._UI状態.モード, this._UI状態.取り消し履歴スタック.length > 0, this._UI状態.表示面)
        this._部品.表示面を切り替える(this._UI状態.表示面)
        this._部品.棚.モードの案内を更新する(this._UI状態.モード)
        this._部品.インスペクター.部品.道路.選択中の道路点があるか設定する(this._UI状態.選択中の道路点 !== null)
        this._対象の道をパネルへ伝える(チャンク.道路一覧)
        this._部品.インスペクター.部品.建物.選択建物有効状態を設定する(this._UI状態.選択中建物識別子 !== null)
        this._部品.インスペクター.モードに応じて表示する(this._UI状態.モード)
        見下ろし図のパネルを同期する(this._部品, this._UI状態, チャンク)
    }

    private _対象の道をパネルへ伝える(道路一覧: 道路の一覧): void {
        const 添字 = this._UI状態.アクティブな道路の添字
        const 設定 = 添字 !== null && 道路一覧.道路が在るか(添字) ? 道路一覧.道路を取り出す(添字) : null
        this._部品.インスペクター.部品.道路.対象の道を設定する(添字, 道路一覧.件数, 設定)
    }
}
