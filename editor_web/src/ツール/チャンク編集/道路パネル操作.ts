import type { 編集対象の道路一覧 } from './編集モデル/index.ts'
import type { 道路点の選択状態, 道路点編集の同期先, 道路点編集の操作先 } from './道路点編集の相手.ts'

// 道路パネルの4つのボタン(選択点を削除・この道を削除・新しい道・全ての道を消す)の中身を担う操作サービス。
// チャンク編集と大域編集で手順が同じであるため、1組をどちらのツールからも使う。
export class 道路パネル操作 {
    public constructor(
        private readonly _道路一覧: 編集対象の道路一覧,
        private readonly _状態: 道路点の選択状態,
        private readonly _操作: 道路点編集の操作先,
        private readonly _同期: 道路点編集の同期先,
    ) {}

    public 選択中の道路点を削除する(): void {
        const 在り処 = this._状態.選択中の道路点
        if (在り処 === null) return
        this._操作.コマンドを実行する({
            種類: '道路点を削除する',
            値: { 対象: this._道路一覧.道路対象を作る(在り処.道路添字), 添字: 在り処.制御点添字 },
        })
        this._状態.選択中の道路点 = null
        this._同期.道路を同期する()
        this._同期.UIを同期する()
    }

    public 対象の道を削除する(): void {
        const 道路添字 = this._状態.アクティブな道路の添字
        if (道路添字 === null || !this._道路一覧.一覧.道路が在るか(道路添字)) return
        this._操作.コマンドを実行する({
            種類: '道路を削除する',
            値: { 対象: this._道路一覧.道路対象を作る(道路添字) },
        })
        this._状態.選択中の道路点 = null
        this._状態.アクティブな道路の添字 = this._削除した後に選ぶ道路添字(道路添字)
        this._同期.道路を同期する()
        this._同期.UIを同期する()
    }

    // 次のクリックから新しい道を始めさせる。道そのものはまだ足さない(空の道を残さないため)。
    public 新しい道を始める(): void {
        this._状態.アクティブな道路の添字 = null
        this._状態.選択中の道路点 = null
        this._同期.道路を同期する()
        this._同期.UIを同期する()
    }

    // 1本ずつ削除のコマンドとして積むため、取り消しも1本ずつ戻る。
    public 全ての道を消す(): void {
        while (this._道路一覧.件数 > 0) {
            this._操作.コマンドを実行する({
                種類: '道路を削除する',
                値: { 対象: this._道路一覧.道路対象を作る(0) },
            })
        }
        this._状態.アクティブな道路の添字 = null
        this._状態.選択中の道路点 = null
        this._同期.道路を同期する()
        this._同期.UIを同期する()
    }

    private _削除した後に選ぶ道路添字(削除した道路添字: number): number | null {
        const 残りの本数 = this._道路一覧.件数
        if (残りの本数 === 0) return null
        return Math.min(削除した道路添字, 残りの本数 - 1)
    }
}
