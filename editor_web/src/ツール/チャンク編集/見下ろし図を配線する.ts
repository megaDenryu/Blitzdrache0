import type { ワールド編集状態 } from './編集モデル/index.ts'
import type { チャンク編集画面部品 } from './画面/index.ts'
import type { チャンク編集状態 } from './チャンク編集状態.ts'
import type { チャンク編集操作サービス } from './チャンク編集操作サービス.ts'
import { 等高線のポインタ操作係 } from './画面/見下ろし図/等高線/等高線のポインタ操作係.ts'
import { 等高線を重ね描きする } from './画面/見下ろし図/等高線/等高線の重ね描き.ts'
import { 粗マスのポインタ操作係 } from './画面/見下ろし図/粗マス/粗マスのポインタ操作係.ts'
import { 粗マスを重ね描きする } from './画面/見下ろし図/粗マス/粗マスの重ね描き.ts'
import { 粗マスの格子 } from './画面/見下ろし図/粗マス/粗マスの座標変換.ts'
import { 入力欄がフォーカス中か } from './画面/三次元/カメラ/キー入力ガード.ts'
import { 例外を帯へ出してコマンドを積む } from './見下ろし図のコマンドを積む.ts'
import { 見下ろし図のパネルを配線する } from './見下ろし図のパネルを配線する.ts'
import { 見下ろし図のパネルを同期する } from './見下ろし図のパネルを同期する.ts'

// 見下ろし図の左ボタンとDeleteキーを、モードに応じて等高線と粗マスの操作係へ振り分け、重ね描きを登録し、
// 右サイドバーの2パネルを配線する。返す関数はwindowへ掛けたキーの購読を外す。
// 重ね描きは描くたびに下書きを読み直すため、コマンドの適用後に全体を同期すれば最新の下書きが出る。
export function 見下ろし図を配線する(
    部品: チャンク編集画面部品,
    状態: チャンク編集状態,
    操作: チャンク編集操作サービス,
    モデル: ワールド編集状態,
): () => void {
    const 積む = 例外を帯へ出してコマンドを積む(部品, 操作)
    const チャンク座標 = (): { x: number; z: number } => ({ ...状態.対象チャンク座標 })
    const チャンク = (): ReturnType<ワールド編集状態['チャンクを取得する']> => モデル.チャンクを取得する(状態.対象チャンク座標)
    const 再描画する = (): void => 部品.見下ろし図.再描画する()
    // 選択(等高線・粗マスとも)はコマンドではなく画面の状態の書き換えであるため、コマンド適用時の全体同期を
    // 待たずここで右サイドバーの表示を直す。
    const パネルを同期する = (): void => 見下ろし図のパネルを同期する(部品, 状態, チャンク())
    const 格子を組む = (一辺の升目数: number): 粗マスの格子 => {
        const 高さ場 = チャンク().高さ場
        return 粗マスの格子.生成する(高さ場.一辺のメートル, 高さ場.格子間隔, 一辺の升目数)
    }

    const 等高線 = new 等高線のポインタ操作係(状態.見下ろし図, {
        等高線一覧を読む: () => チャンク().下書き.等高線一覧を取得する(),
        視点を読む: () => 部品.見下ろし図.視点,
        等高線を追加する: (線) => 積む({ 種類: '等高線を追加する', 値: { チャンク座標: チャンク座標(), 等高線: 線 } }),
        等高線を変更する: (添字, 線) => 積む({ 種類: '等高線を変更する', 値: { チャンク座標: チャンク座標(), 添字, 等高線: 線 } }),
        等高線を削除する: (添字) => 積む({ 種類: '等高線を削除する', 値: { チャンク座標: チャンク座標(), 添字 } }),
        再描画する,
    })
    const 粗マス = new 粗マスのポインタ操作係(状態.見下ろし図, {
        格子を読む: () => 格子を組む(状態.見下ろし図.粗マスの一辺の升目数),
        粗マスを塗る: (一辺, 塗り一覧) => 積む({ 種類: '粗マスを塗る', 値: { チャンク座標: チャンク座標(), 粗マスの一辺の升目数: 一辺, 塗り一覧: [...塗り一覧] } }),
        粗マスを選択する: (番地) => {
            状態.見下ろし図.選択中の粗マスの番地 = 番地
            状態.見下ろし図.選択中の粗マスを選んだ一辺の升目数 = チャンク().下書き.粗マスの一辺の升目数を取得する()
        },
        再描画する,
    })

    部品.見下ろし図.配線する({
        on左ボタン押下: (位置, 原初事象) => {
            if (状態.モード === '等高線') { 等高線.押された(位置, 原初事象); パネルを同期する() }
            if (状態.モード === '粗マス') 粗マス.押された(位置, 原初事象)
        },
        on左ボタン移動: (位置, 押下中) => {
            if (状態.モード === '等高線') 等高線.動かされた(位置, 押下中)
            if (状態.モード === '粗マス') 粗マス.動かされた(位置, 押下中)
        },
        on左ボタン離し: (_位置, 原初事象) => {
            if (状態.モード === '等高線') 等高線.離された()
            if (状態.モード === '粗マス') 粗マス.離された(原初事象)
            パネルを同期する()
        },
    })

    部品.見下ろし図.重ね描きを登録する((文脈, 視点) => {
        const 下書き = チャンク().下書き
        粗マスを重ね描きする(文脈, 視点, {
            格子: 格子を組む(下書き.粗マスの一辺の升目数を取得する()),
            塗っている途中の格子: 格子を組む(状態.見下ろし図.粗マスの一辺の升目数),
            塗り一覧: 下書き.粗マスの塗り一覧を取得する(),
            材質色: 部品.見下ろし図.下地の配色.材質色,
            塗っている途中の番地一覧: 粗マス.通った番地一覧,
            格子線を描くか: 状態.モード === '粗マス',
            選択中の番地: 状態.見下ろし図.選択中の粗マスの番地,
        })
        等高線を重ね描きする(文脈, 視点, 等高線.重ね描きの入力を作る())
    })

    見下ろし図のパネルを配線する(部品, 状態, 積む, () => チャンク().下書き)

    // Deleteは選んだ等高線を消す。数値の欄で文字を消しているときに線が消えないよう入力欄のフォーカスを見る。
    const キー押下処理 = (事象: KeyboardEvent): void => {
        if (事象.key !== 'Delete' || 状態.モード !== '等高線' || 状態.表示面 !== '見下ろし図' || 入力欄がフォーカス中か()) return
        事象.preventDefault()
        等高線.選択中の線を削除する()
    }
    window.addEventListener('keydown', キー押下処理)
    return () => window.removeEventListener('keydown', キー押下処理)
}
