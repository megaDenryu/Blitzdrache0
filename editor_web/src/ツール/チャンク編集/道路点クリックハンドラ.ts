import type { 位置3次元 } from '../../生成/編集資源契約.ts'
import type { 編集対象の道路一覧 } from './編集モデル/index.ts'
import { 当たった道路点の在り処を求める, 路面への割り込み先を求める } from './道路の当たり判定.ts'
import type {
    当たりの記録,
    道路点の選択状態,
    道路点編集の同期先,
    道路点編集の操作先,
    道路点編集対象ビュー,
} from './道路点編集の相手.ts'

// 道路点のクリック編集を担う操作サービス。道を描き足す・分岐を始める・点を選ぶ・帯へ割り込ませるの
// 4つを持ち、チャンク編集と大域編集の両方の道路モードから同じ手順で呼ばれる。
export class 道路点クリックハンドラ {
    public constructor(
        private readonly _道路一覧: 編集対象の道路一覧,
        private readonly _状態: 道路点の選択状態,
        private readonly _ビュー: 道路点編集対象ビュー,
        private readonly _操作: 道路点編集の操作先,
        private readonly _同期: 道路点編集の同期先,
        // 広域道路は大域地形より少し浮かせて置くため、追加する点をこの高さだけ持ち上げる。
        private readonly _追加時に持ち上げるメートル: number = 0,
    ) {}

    // アクティブな道の終わりへ点を足す。まだ道が無い(アクティブがnull)なら、その点を先頭に持つ道を1本始める。
    public 描き足す(交差点: 位置3次元): void {
        const 位置 = { x: 交差点.x, y: 交差点.y + this._追加時に持ち上げるメートル, z: 交差点.z }
        const アクティブ = this._状態.アクティブな道路の添字
        if (アクティブ === null || !this._道路一覧.一覧.道路が在るか(アクティブ)) {
            this._道を1本始める([位置], null)
            return
        }
        this._操作.コマンドを実行する({
            種類: '道路点を追加する',
            値: { 対象: this._道路一覧.道路対象を作る(アクティブ), 位置 },
        })
    }

    // 既存の道路点の上をクリックしたら、その点を先頭に共有する新しい道を始める(分岐)。始めたらtrueを返す。
    public 分岐を始める(当たり一覧: readonly 当たりの記録[]): boolean {
        const 在り処 = 当たった道路点の在り処を求める(当たり一覧, this._ビュー.道路点マーカー)
        if (在り処 === null) return false
        const 分かれ元の点 = this._道路一覧.道路点の位置を求める(在り処)
        if (分かれ元の点 === null) return false
        this._道を1本始める([{ ...分かれ元の点 }], 在り処.道路添字)
        return true
    }

    // 道を1本も持たない状態へ戻し、次に地形をクリックしたところから新しい道を始めさせる。
    public 次のクリックから新しい道にする(): void {
        this._状態.アクティブな道路の添字 = null
        this._状態.選択中の道路点 = null
        this._同期.道路を同期する()
        this._同期.UIを同期する()
    }

    // マーカーに当たっていればその道路点を選ぶ。選べたらtrueを返す。選んだ点の道がアクティブになる。
    public 道路点を選択する(当たり一覧: readonly 当たりの記録[]): boolean {
        const 在り処 = 当たった道路点の在り処を求める(当たり一覧, this._ビュー.道路点マーカー)
        if (在り処 === null) return false
        this._状態.選択中の道路点 = 在り処
        this._状態.アクティブな道路の添字 = 在り処.道路添字
        this._同期.道路を同期する()
        this._同期.UIを同期する()
        return true
    }

    // 路面の上に当たっていれば、その道のいちばん近い区間へ点を割り込ませる。割り込ませたらtrueを返す。
    public 帯の上へ挿入する(当たり一覧: readonly 当たりの記録[]): boolean {
        const 割り込み先 = 路面への割り込み先を求める(当たり一覧, this._ビュー.道路帯, this._道路一覧)
        if (割り込み先 === null) return false
        const { 道路添字, 挿入先 } = 割り込み先
        this._操作.コマンドを実行する({
            種類: '道路点を挿入する',
            値: { 対象: this._道路一覧.道路対象を作る(道路添字), 添字: 挿入先.添字, 位置: 挿入先.位置 },
        })
        this._状態.選択中の道路点 = { 道路添字, 制御点添字: 挿入先.添字 }
        this._状態.アクティブな道路の添字 = 道路添字
        this._同期.道路を同期する()
        this._同期.UIを同期する()
        return true
    }

    private _道を1本始める(制御点列: readonly 位置3次元[], 設定を受け継ぐ道路添字: number | null): void {
        this._操作.コマンドを実行する({
            種類: '道路を追加する',
            値: this._道路一覧.道路を足すコマンドを作る(制御点列, 設定を受け継ぐ道路添字),
        })
        this._状態.アクティブな道路の添字 = this._道路一覧.件数 - 1
        this._同期.道路を同期する()
        this._同期.UIを同期する()
    }

}
