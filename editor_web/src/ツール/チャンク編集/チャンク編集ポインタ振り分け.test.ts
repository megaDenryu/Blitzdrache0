import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import {
    チャンク座標,
    マーカーへの当たり一覧,
    入力一式を組む,
    初期状態を作る,
    地形への当たり一覧,
    押した回数が1回のクリック事象を作る,
} from './道路の入力試験の下ごしらえ.ts'

// 分岐の手順そのものは道路点クリックハンドラの試験が見る。ここが見るのは、ポインタの振り分けが
// モード=道作成でマーカーの当たりを受けたときに分岐まで到達するか、である。
// 実UIでは、押した時点でドラッグがマーカーをつかみ、わずかな手ぶれで点が動いた扱いになって
// クリックが読み飛ばされ、分岐に至らなかった。その経路をここで固定する。

const 左ボタン = 0

describe('チャンク編集ポインタ振り分け', () => {
    it('道作成モードでは道路点をつかまないこと', () => {
        const モデル = 初期状態を作る()
        const { 選択状態, 振り分け } = 入力一式を組む(モデル, { 道路添字: 0, 制御点添字: 1 }, '道作成')

        assert.strictEqual(振り分け.押された(左ボタン, マーカーへの当たり一覧), false, 'つかまないこと')
        assert.strictEqual(選択状態.つかんでいる道路点, null, 'つかんでいる点が残らないこと')
    })

    it('道編集モードでは道路点をつかむこと', () => {
        const モデル = 初期状態を作る()
        const { 選択状態, 振り分け } = 入力一式を組む(モデル, { 道路添字: 0, 制御点添字: 1 }, '道編集')

        assert.strictEqual(振り分け.押された(左ボタン, マーカーへの当たり一覧), true, 'つかむこと')
        assert.deepStrictEqual(選択状態.つかんでいる道路点, { 道路添字: 0, 制御点添字: 1 })
    })

    it('道作成モードで押す・動かす・離すを経てもクリックが分岐に至ること', () => {
        const モデル = 初期状態を作る()
        const { 選択状態, 振り分け } = 入力一式を組む(モデル, { 道路添字: 0, 制御点添字: 1 }, '道作成')
        const 道路一覧 = モデル.チャンクを取得する(チャンク座標).道路一覧
        const 元の制御点列 = 道路一覧.道路を取り出す(0).制御点列.map((点) => ({ ...点 }))

        振り分け.押された(左ボタン, マーカーへの当たり一覧)
        // 手ぶれぶんの移動。地形の当たりが在っても、つかんでいないので点は動かないはずである。
        振り分け.動かされた(地形への当たり一覧)
        振り分け.離された(左ボタン)
        振り分け.クリックされた(押した回数が1回のクリック事象を作る(マーカーへの当たり一覧))

        assert.deepStrictEqual(道路一覧.道路を取り出す(0).制御点列, 元の制御点列, '分かれ元の点が動かないこと')
        assert.strictEqual(道路一覧.件数, 2, '道が1本増えること')
        assert.strictEqual(選択状態.アクティブな道路の添字, 1, 'アクティブが新しい道へ移ること')
        assert.deepStrictEqual(
            道路一覧.道路を取り出す(1).制御点列,
            [{ x: 10, y: 2, z: 0 }],
            '分かれ元の点と同じ位置を先頭に持つこと',
        )
    })

    it('道作成モードで地形をクリックすると、アクティブな道の終わりへ点が足されること', () => {
        const モデル = 初期状態を作る()
        const { 振り分け } = 入力一式を組む(モデル, null, '道作成')
        const 道路一覧 = モデル.チャンクを取得する(チャンク座標).道路一覧

        振り分け.クリックされた(押した回数が1回のクリック事象を作る(地形への当たり一覧))

        assert.strictEqual(道路一覧.件数, 1, '道の本数は変わらないこと')
        assert.deepStrictEqual(道路一覧.道路を取り出す(0).制御点列.at(-1), { x: 4, y: 5, z: 6 })
    })

    it('道編集モードでマーカーをクリックすると、分岐せずその点が選ばれること', () => {
        const モデル = 初期状態を作る()
        const { 選択状態, 振り分け } = 入力一式を組む(モデル, { 道路添字: 0, 制御点添字: 0 }, '道編集')
        const 道路一覧 = モデル.チャンクを取得する(チャンク座標).道路一覧

        振り分け.クリックされた(押した回数が1回のクリック事象を作る(マーカーへの当たり一覧))

        assert.strictEqual(道路一覧.件数, 1, '道が増えないこと')
        assert.deepStrictEqual(選択状態.選択中の道路点, { 道路添字: 0, 制御点添字: 0 })
    })
})
