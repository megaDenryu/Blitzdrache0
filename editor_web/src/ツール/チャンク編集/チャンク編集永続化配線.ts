import type { プロジェクト保管庫接続 } from '../../境界/通信/index.ts'
import { 保存状態サービス } from '../../境界/通信/index.ts'
import type { チャンク座標 } from '../../生成/編集資源契約.ts'
import type { ワールド編集状態 } from './編集モデル/index.ts'
import type { 永続化パネル } from './画面/パネル/永続化/index.ts'
import type { チャンク編集同期サービス } from './チャンク編集同期サービス.ts'
import type { ワールド永続化サービス } from './操作コマンド/index.ts'
import { パネル操作を実行する, type パネル操作結果 } from './永続化パネル操作.ts'

// 永続化パネルの保存・読み込みボタンと永続化サービスを配線する。
export function 永続化イベントを配線する(
    パネル: 永続化パネル,
    永続化: ワールド永続化サービス,
    保管庫: プロジェクト保管庫接続,
    モデル: ワールド編集状態,
    同期: チャンク編集同期サービス,
    対象座標: チャンク座標,
): () => void {
    let 購読解除 = (): void => {}
    if ('通知' in 保管庫 && 保管庫.通知 instanceof 保存状態サービス) {
        購読解除 = 保管庫.通知.チャンク状態を購読する(対象座標, (状態) => {
            パネル.状態文言を更新する(状態.文言, 状態.エラーか)
        })
    }

    const 保存する = async (): Promise<パネル操作結果> => {
        await 永続化.保存する(モデル)
        return { 文言: '保存完了', エラーか: false }
    }
    const 読み込む = async (): Promise<パネル操作結果> => {
        const 結果 = await 永続化.チャンクを読み込む(対象座標)
        モデル.状態を上書きする(結果.状態)
        同期.全体を同期する()
        const 表示 = 結果.結果種別 === '読込成功' ? '読み込み完了' : '初期ワールド生成'
        return { 文言: 表示, エラーか: false }
    }

    パネル.on保存クリック(() => { void パネル操作を実行する(パネル, '保存中...', 保存する, '保存失敗') })
    パネル.on読込クリック(() => { void パネル操作を実行する(パネル, '読み込み中...', 読み込む, '読込失敗') })

    return 購読解除
}

export async function 起動時にワールドを読み込む(
    パネル: 永続化パネル,
    永続化: ワールド永続化サービス,
    モデル: ワールド編集状態,
    同期: チャンク編集同期サービス,
    対象座標: チャンク座標,
): Promise<void> {
    try {
        const 結果 = await 永続化.チャンクを読み込む(対象座標)
        if (結果.結果種別 === '読込成功') {
            モデル.状態を上書きする(結果.状態)
            同期.全体を同期する()
            パネル.状態文言を更新する('読込完了(起動時)', false)
        } else {
            パネル.状態文言を更新する('未保存(初期生成)', false)
        }
    } catch (原因: unknown) {
        const メッセージ = 原因 instanceof Error ? 原因.message : String(原因)
        パネル.状態文言を更新する(`起動時読込失敗: ${メッセージ}`, true)
    }
}
