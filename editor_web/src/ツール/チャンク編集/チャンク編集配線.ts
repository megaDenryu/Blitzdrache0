import type { ワールド編集状態 } from './編集モデル/index.ts'
import type { チャンク編集画面部品 } from './画面/index.ts'
import type { チャンク編集状態 } from './チャンク編集状態.ts'
import type { チャンク編集操作サービス } from './チャンク編集操作サービス.ts'
import type { チャンク編集同期サービス } from './チャンク編集同期サービス.ts'
import { 棚の出来事を配線する } from './チャンク編集の棚を配線する.ts'
import { 道路パネルを配線する } from './道路パネルを配線する.ts'
import { 見下ろし図を配線する } from './見下ろし図を配線する.ts'

// エディタ領域の操作帯・下パネルの棚・右サイドバーのインスペクターの出来事を、
// 操作サービスと同期サービスへ配線ポート経由で接続する。返す関数はwindowへ掛けた購読を外す。
export function パネルイベントを配線する(
    部品: チャンク編集画面部品,
    状態: チャンク編集状態,
    操作: チャンク編集操作サービス,
    同期: チャンク編集同期サービス,
    モデル: ワールド編集状態,
): () => void {
    部品.操作帯.配線する({
        onモード変更: (モード) => 操作.モードを移す(モード),
        on取り消す: () => 操作.直前の操作を取り消す(),
        on地形追従変更: (有効) => {
            部品.三次元ビュー.カメラ制御.地形追従を設定する(有効)
        },
        on表示面変更: (面) => {
            状態.表示面 = 面
            同期.UIを同期する()
        },
    })
    const 見下ろし図の解除 = 見下ろし図を配線する(部品, 状態, 操作, モデル)
    棚の出来事を配線する(部品, 状態, 操作)
    道路パネルを配線する(部品, 状態, 操作, 同期, モデル)
    部品.インスペクター.部品.地表の焼き直し.配線する({
        on急勾配ベイク: () => 操作.コマンドを実行する({ 種類: '急勾配を岩肌へベイクする', 値: { チャンク座標: { ...状態.対象チャンク座標 } } }),
        on道路下泥ベイク: () => 操作.コマンドを実行する({ 種類: '道路下を泥へベイクする', 値: { チャンク座標: { ...状態.対象チャンク座標 } } }),
        on道路の泥の追従方針変更: (方針) => { モデル.道路の泥の追従方針 = 方針 },
    })
    部品.インスペクター.部品.建物.配線する({
        on基礎平坦化: () => 操作.基礎を平坦化する(),
        on地面接地: () => 操作.建物を地面へ接地させる(),
        on建物削除: () => {
            if (状態.選択中建物識別子 === null) return
            操作.コマンドを実行する({ 種類: '建物を削除する', 値: { チャンク座標: { ...状態.対象チャンク座標 }, 識別子: 状態.選択中建物識別子 } })
            状態.選択中建物識別子 = null
            同期.建物を同期する()
            同期.UIを同期する()
        },
    })
    部品.インスペクター.部品.散布.配線する({
        on最小間隔変更: (間隔) => {
            const チャンク = モデル.チャンクを取得する(状態.対象チャンク座標)
            チャンク.散布.最小間隔メートル = 間隔
            同期.散布を同期する()
        },
        on散布再ベイク: () => {
            const チャンク = モデル.チャンクを取得する(状態.対象チャンク座標)
            チャンク.散布.乱数の種 = チャンク.散布.乱数の種 + 1n
            同期.散布を同期する()
        },
    })
    return 見下ろし図の解除
}
