import type { 編集モード } from './画面/パネル/モード切替/モード定義.ts'
import type { 建物を選ぶ相手 } from './建物のクリック選択.ts'
import type { 道路点クリックハンドラ } from './道路点クリックハンドラ.ts'
import type { 道路点ドラッグハンドラ } from './道路点ドラッグハンドラ.ts'
import type { ポインタ事象の記録, 当たりの記録, 当たりの主 } from './道路点編集の相手.ts'

// ポインタ事象をモードで振り分ける操作サービス。押す・動かす・離す・クリックの4つを1箇所で
// 受け持ち、どのモードでどの操作が起きるかの決定をここへ閉じる。
//
// 注意: 道路点をつかんで動かせるのは道編集モードだけである。道作成モードでもつかめるようにすると、
// 分岐のために既存の点をクリックした瞬間にドラッグとして扱われ、わずかな手ぶれで点が地形の
// 当たり位置へ飛び、離したあとのクリックも読み飛ばされて分岐に至らない。
export class チャンク編集ポインタ振り分け {
    public constructor(
        private readonly _状態: { モード: 編集モード },
        private readonly _地形: 当たりの主,
        private readonly _道路点クリック: 道路点クリックハンドラ,
        private readonly _道路点ドラッグ: 道路点ドラッグハンドラ,
        private readonly _建物選択: 建物を選ぶ相手,
    ) {}

    // 道路点をつかめたらtrueを返す。呼び出し元はそのとき筆致もカメラ操作も走らせない。
    public 押された(ボタン: number, 当たり一覧: readonly 当たりの記録[]): boolean {
        if (this._状態.モード !== '道編集') return false
        return this._道路点ドラッグ.押された(ボタン, 当たり一覧)
    }

    public 動かされた(当たり一覧: readonly 当たりの記録[]): boolean {
        return this._道路点ドラッグ.動かされた(当たり一覧)
    }

    public 離された(ボタン: number): void {
        this._道路点ドラッグ.離された(ボタン)
    }

    public クリックされた(事象: ポインタ事象の記録): void {
        // 動かして離した直後のクリックは、動かした先での選択や挿入になるため読み飛ばす。
        if (this._道路点ドラッグ.ドラッグ直後のクリックか) {
            this._道路点ドラッグ.クリックの読み飛ばしを終える()
            return
        }
        if (this._状態.モード === '道作成') {
            this._道を描く(事象)
            return
        }
        if (this._状態.モード === '道編集') {
            // 点の上のクリックは選択を優先し、点に当たらず帯の上だったときだけ点を割り込ませる。
            if (!this._道路点クリック.道路点を選択する(事象.当たり一覧)) {
                this._道路点クリック.帯の上へ挿入する(事象.当たり一覧)
            }
            return
        }
        if (this._状態.モード === '建物' || this._状態.モード === '選択') {
            this._建物選択.選ぶ(事象.当たり一覧)
        }
    }

    // 既存の点の上なら分岐を始め、地形の上なら描き足す。地形のダブルクリックは、
    // 2回目のクリックで点を足さずに道を終え、次のクリックから新しい道を始める合図にする。
    private _道を描く(事象: ポインタ事象の記録): void {
        if (this._道路点クリック.分岐を始める(事象.当たり一覧)) return
        const 最前面当たり = 事象.最前面当たり
        if (最前面当たり === null || 最前面当たり.部品.実体 !== this._地形.実体) return
        if (事象.原初事象.detail >= 2) {
            this._道路点クリック.次のクリックから新しい道にする()
            return
        }
        const 交差点 = 最前面当たり.交差点
        this._道路点クリック.描き足す({ x: 交差点.x, y: 交差点.y, z: 交差点.z })
    }
}
