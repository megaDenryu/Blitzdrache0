import { Object3D, Vector3 } from 'three'
import type { 編集コマンド, 大域世界構造, チャンク構造 } from '../../生成/編集資源契約.ts'
import { ワールド編集状態, 編集対象の道路一覧, 空の見下ろし図の下書き } from './編集モデル/index.ts'
import type { 道路点の在り処 } from './編集モデル/index.ts'
import { 編集コマンドを適用する } from './操作コマンド/index.ts'
import { チャンク編集ポインタ振り分け } from './チャンク編集ポインタ振り分け.ts'
import { 道路点クリックハンドラ } from './道路点クリックハンドラ.ts'
import { 道路点ドラッグハンドラ } from './道路点ドラッグハンドラ.ts'
import type { 編集モード } from './画面/パネル/モード切替/モード定義.ts'
import type { 当たりの記録, 道路点の選択状態 } from './道路点編集の相手.ts'

// 道路の入力(クリック・ドラッグ・振り分け)の試験が使う、道が1本だけ在るチャンクと入力一式の組み立て。
// 当たり判定は決め打ちの偽物へ差し替え、道の増え方とアクティブな道の移り方だけを見る。

export const チャンク座標 = { x: 0, z: 0 }

// 当たり一覧が指す先。マーカーへ当たったことにするため、マーカーの実体と同じ物体を使う。
const マーカーの物体 = new Object3D()
const 地形の物体 = new Object3D()

export function 初期状態を作る(): ワールド編集状態 {
    const 大域構造: 大域世界構造 = {
        区画割り: { 一辺のメートル: 512, 軸あたりチャンク数: 2, チャンクあたり格子解像度: 33 },
        広域道路一覧: [],
    }
    const 状態 = new ワールド編集状態(大域構造)
    const 構造: チャンク構造 = {
        道路一覧: [{
            制御点列: [{ x: -10, y: 1, z: 0 }, { x: 10, y: 2, z: 0 }],
            全幅メートル: 7,
            散布除外バッファメートル: 13,
            細分割数: 40,
        }],
        建物一覧: [],
        散布: { 最小間隔メートル: 5, 乱数の種: 1n },
        散布の個体一覧: [],
        見下ろし図の下書き: 空の見下ろし図の下書き(),
    }
    状態.チャンクを登録する(チャンク座標, 構造)
    状態.選択中チャンク座標 = チャンク座標
    return 状態
}

// マーカーの代わりに、渡した在り処を必ず返す当たり判定を置く。実際の描画は絵の目視で確かめる。
export function 入力一式を組む(
    モデル: ワールド編集状態,
    当たる在り処: 道路点の在り処 | null,
    初期モード: 編集モード = '道作成',
) {
    const 道路一覧 = new 編集対象の道路一覧(モデル, { 種類: 'チャンク', チャンク座標 })
    const 選択状態: 道路点の選択状態 = { アクティブな道路の添字: 0, 選択中の道路点: null, つかんでいる道路点: null }
    const モード状態: { モード: 編集モード } = { モード: 初期モード }
    const 地形 = { 実体: 地形の物体 }
    const ビュー = {
        道路点マーカー: { 実体: マーカーの物体, 当たった道路点の在り処を求める: (): 道路点の在り処 | null => 当たる在り処 },
        道路帯: { 実体: new Object3D(), 当たった路面の道路添字を求める: (): number | null => null },
        地形,
    }
    const 操作 = { コマンドを実行する: (コマンド: 編集コマンド) => { 編集コマンドを適用する(モデル, コマンド) } }
    const 同期 = { 道路を同期する: () => {}, UIを同期する: () => {} }
    const クリック = new 道路点クリックハンドラ(道路一覧, 選択状態, ビュー, 操作, 同期)
    const ドラッグ = new 道路点ドラッグハンドラ(道路一覧, 選択状態, ビュー, 操作, 同期)
    const 建物選択 = { 選ぶ: (): boolean => false }
    return {
        選択状態,
        モード状態,
        クリック,
        ドラッグ,
        振り分け: new チャンク編集ポインタ振り分け(モード状態, 地形, クリック, ドラッグ, 建物選択),
    }
}

function 当たりを1件作る(物体: Object3D): 当たりの記録 {
    return { 部品: { 実体: 物体 }, 交差点: new Vector3(4, 5, 6), 原初交差情報: { object: 物体 } }
}

export const マーカーへの当たり一覧: readonly 当たりの記録[] = [当たりを1件作る(マーカーの物体)]
export const 地形への当たり一覧: readonly 当たりの記録[] = [当たりを1件作る(地形の物体)]

export function 押した回数が1回のクリック事象を作る(当たり一覧: readonly 当たりの記録[]) {
    return { 当たり一覧, 最前面当たり: 当たり一覧[0] ?? null, 原初事象: { detail: 1 } }
}
