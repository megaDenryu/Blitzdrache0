import type { 平面の位置 } from '../../../生成/編集資源契約.ts'

// 高さ場から等高線を導く計算の第1工程。1つの高さについて、マーチングスクエア法で各升目から等値線の線分を
// 集める。受け取るのは高さ格子と1つの高さ、返すのは繋がっていない線分の一覧である。
// 参照: `_doc/設計/見下ろし図による地形編集.md`「判断5」。

const 長さ0とみなすメートル = 1e-9

export type 等値線の線分 = {
    readonly 始点: 平面の位置
    readonly 終点: 平面の位置
}

// 升目の4角を左上a(1)・右上b(2)・右下c(4)・左下d(8)のビットにし、高さ以上の角の組み合わせ(1から14)ごとに
// 線分が横切る辺の対を持つ。辺は0=上(a-b)・1=右(b-c)・2=下(d-c)・3=左(a-d)。対角だけが高い5と10は、
// 2本の線分が高い角どうしを分ける向きに固定して、同じ格子から常に同じ線分が出るようにする。
const 辺の対の表: ReadonlyArray<ReadonlyArray<readonly [number, number]>> = [
    [], [[3, 0]], [[0, 1]], [[3, 1]], [[1, 2]], [[3, 0], [1, 2]], [[0, 2]], [[3, 2]],
    [[2, 3]], [[0, 2]], [[0, 1], [2, 3]], [[1, 2]], [[1, 3]], [[0, 1]], [[3, 0]], [],
]

export function 等値線の線分を抽出する(
    格子データ: Float32Array,
    解像度: number,
    一辺のメートル: number,
    高さ: number,
): Array<等値線の線分> {
    const 格子間隔 = 一辺のメートル / (解像度 - 1)
    const 位置 = (gx: number, gz: number): 平面の位置 => ({ x: gx * 格子間隔 - 一辺のメートル / 2, z: gz * 格子間隔 - 一辺のメートル / 2 })
    const 線分一覧: Array<等値線の線分> = []
    for (let gz = 0; gz < 解像度 - 1; gz++) {
        for (let gx = 0; gx < 解像度 - 1; gx++) {
            const ha = 格子データ[gz * 解像度 + gx] ?? 0
            const hb = 格子データ[gz * 解像度 + gx + 1] ?? 0
            const hc = 格子データ[(gz + 1) * 解像度 + gx + 1] ?? 0
            const hd = 格子データ[(gz + 1) * 解像度 + gx] ?? 0
            const 場合 = (ha >= 高さ ? 1 : 0) | (hb >= 高さ ? 2 : 0) | (hc >= 高さ ? 4 : 0) | (hd >= 高さ ? 8 : 0)
            const 辺の位置 = [
                辺上の位置(位置(gx, gz), ha, 位置(gx + 1, gz), hb, 高さ),
                辺上の位置(位置(gx + 1, gz), hb, 位置(gx + 1, gz + 1), hc, 高さ),
                辺上の位置(位置(gx, gz + 1), hd, 位置(gx + 1, gz + 1), hc, 高さ),
                辺上の位置(位置(gx, gz), ha, 位置(gx, gz + 1), hd, 高さ),
            ]
            for (const [辺1, 辺2] of 辺の対の表[場合] ?? []) {
                const 始点 = 辺の位置[辺1]
                const 終点 = 辺の位置[辺2]
                if (始点 === undefined || 終点 === undefined) continue
                // 角の高さがちょうど等しいと2つの辺の交点がその角に重なり、長さ0の線分が出る。連結で端点を共有する
                // 線分が3本以上になって折れ線が途切れるため、ここで落とす。
                if (Math.hypot(終点.x - 始点.x, 終点.z - 始点.z) < 長さ0とみなすメートル) continue
                線分一覧.push({ 始点, 終点 })
            }
        }
    }
    return 線分一覧
}

// 辺の両端の高さで線形に補間して、辺の上で高さがちょうど等しくなる位置を求める。
// 両端が同じ高さの辺は表の上では横切られないため、中点を返しておけば使われない。
function 辺上の位置(p0: 平面の位置, h0: number, p1: 平面の位置, h1: number, 高さ: number): 平面の位置 {
    const t = h1 === h0 ? 0.5 : Math.min(1, Math.max(0, (高さ - h0) / (h1 - h0)))
    return { x: p0.x + (p1.x - p0.x) * t, z: p0.z + (p1.z - p0.z) * t }
}
