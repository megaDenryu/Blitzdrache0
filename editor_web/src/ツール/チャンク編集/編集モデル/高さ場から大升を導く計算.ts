import type { 大升の塗り } from '../../../生成/編集資源契約.ts'
import { 大升の分割を求める, 大升ごとの升内平均を求める } from './大升の格子分割.ts'
import { 地表材質層の数, 添字を地表材質層に変換する } from './地表材質層の添字.ts'

// 高さ格子と材質重みから大升の塗りを導く純粋計算。大升ごとに、含まれる格子点の平均を高さに、
// 重みの合計が最大の層を層にする。全ての大升を塗りとして返す(情報が落ちることを前提にした逆変換)。
// 参照: `_doc/設計/見下ろし図による地形編集.md`「判断5」。
export function 高さ場から大升を導く(
    一辺の升目数: number,
    解像度: number,
    格子データ: Float32Array,
    材質データ: Uint8Array,
): Array<大升の塗り> {
    const 分割 = 大升の分割を求める(解像度, 一辺の升目数)
    const 平均 = 大升ごとの升内平均を求める(分割, 解像度, 格子データ, 材質データ)
    const 塗り一覧: Array<大升の塗り> = []
    for (let 行 = 0; 行 < 分割.軸あたり大升数; 行++) {
        for (let 列 = 0; 列 < 分割.軸あたり大升数; 列++) {
            const 大升添字 = 行 * 分割.軸あたり大升数 + 列
            let 最大の層 = 0
            for (let 層 = 1; 層 < 地表材質層の数; 層++) {
                if ((平均.重み平均[大升添字 * 地表材質層の数 + 層] ?? 0) > (平均.重み平均[大升添字 * 地表材質層の数 + 最大の層] ?? 0)) {
                    最大の層 = 層
                }
            }
            塗り一覧.push({
                列,
                行,
                高さメートル: 平均.高さ平均[大升添字] ?? 0,
                層: 添字を地表材質層に変換する(最大の層),
            })
        }
    }
    return 塗り一覧
}
