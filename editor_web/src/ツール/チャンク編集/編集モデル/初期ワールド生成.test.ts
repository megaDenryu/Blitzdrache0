import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 初期ワールド状態を生成する } from './初期ワールド生成.ts'

describe('初期ワールド生成のチャンク座標決定性テスト', () => {
    it('同一チャンク座標からは完全に同一の初期地形と散布乱数種が生成されること', () => {
        const 座標 = { x: 1, z: 2 }
        const 状態A = 初期ワールド状態を生成する(座標)
        const 状態B = 初期ワールド状態を生成する(座標)

        const チャンクA = 状態A.チャンクを取得する(座標)
        const チャンクB = 状態B.チャンクを取得する(座標)

        assert.strictEqual(
            チャンクA.散布.乱数の種,
            チャンクB.散布.乱数の種,
            '散布乱数の種が完全に一致すること',
        )

        assert.deepStrictEqual(
            チャンクA.高さ場.格子データ,
            チャンクB.高さ場.格子データ,
            '高さ場の格子データが完全に一致すること',
        )
        assert.deepStrictEqual(
            チャンクA.地表材質.材質データ,
            チャンクB.地表材質.材質データ,
            '材質データが完全に一致すること',
        )
    })

    it('異なるチャンク座標からは異なる地形と散布乱数種が生成されること', () => {
        const 状態1 = 初期ワールド状態を生成する({ x: 0, z: 0 })
        const 状態2 = 初期ワールド状態を生成する({ x: 1, z: 0 })

        const チャンク1 = 状態1.チャンクを取得する({ x: 0, z: 0 })
        const チャンク2 = 状態2.チャンクを取得する({ x: 1, z: 0 })

        assert.notStrictEqual(
            チャンク1.散布.乱数の種,
            チャンク2.散布.乱数の種,
            '異なるチャンク座標では異なる散布乱数の種になること',
        )

        let 相違点数 = 0
        for (let i = 0; i < チャンク1.高さ場.格子データ.length; i++) {
            if (チャンク1.高さ場.格子データ[i] !== チャンク2.高さ場.格子データ[i]) {
                相違点数++
            }
        }
        assert.ok(相違点数 > 0, '異なるチャンク座標では異なる高さ格子になること')
    })

    it('大域から切り出した高さデータを渡すと、座標を種にした合成でなくそれが高さ場になること', () => {
        const 座標 = { x: 1, z: 2 }
        const 大域構造 = {
            区画割り: { 一辺のメートル: 512, 軸あたりチャンク数: 2, チャンクあたり格子解像度: 4 },
            広域道路一覧: [{ 制御点列: [], 全幅メートル: 8, 細分割数: 80 }],
        }
        const 頂点数 = 5
        const 切り出した高さ = new Float32Array(頂点数 * 頂点数)
        for (let i = 0; i < 切り出した高さ.length; i++) {
            切り出した高さ[i] = i * 0.25
        }

        const 状態 = 初期ワールド状態を生成する(座標, 大域構造, 切り出した高さ)

        assert.deepStrictEqual(
            Array.from(状態.チャンクを取得する(座標).高さ場.格子データ),
            Array.from(切り出した高さ),
        )
    })

    it('初期材質データが単色のべた塗りではなく、草以外の重みも含むこと', () => {
        const 状態 = 初期ワールド状態を生成する({ x: 0, z: 0 })
        const チャンク = 状態.チャンクを取得する({ x: 0, z: 0 })
        const 材質データ = チャンク.地表材質.材質データ
        const 草重み一覧 = new Set<number>()
        let 草以外がある画素数 = 0
        for (let i = 0; i < 材質データ.length / 4; i++) {
            const 草 = 材質データ[i * 4 + 0] ?? 0
            草重み一覧.add(草)
            if (草 < 255) 草以外がある画素数++
        }
        assert.ok(草重み一覧.size > 1, '草の重みが画素間で複数の値を取るべき(単色のべた塗りではない)')
        assert.ok(草以外がある画素数 > 0, '草100%ではない画素(泥・岩の混入)が存在するべき')
    })
})
