import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 地表材質 } from './地表材質.ts'
import { 高さ場 } from './高さ場.ts'

describe('地表材質のベイク', () => {
    it('急勾配ベイクで崖面が岩肌になり合計255が保たれること', () => {
        const 解像度 = 17
        const 一辺 = 32
        const 対象高さ場 = new 高さ場(解像度, 一辺)
        for (let gz = 0; gz < 解像度; gz++) {
            for (let gx = 0; gx < 解像度; gx++) {
                対象高さ場.格子データ[gz * 解像度 + gx] = gx * 10
            }
        }
        const 対象材質 = new 地表材質(解像度, 一辺)
        対象材質.急勾配を岩肌へベイクする(対象高さ場)

        for (let i = 0; i < 解像度 * 解像度; i++) {
            const r = 対象材質.材質データ[i * 4 + 0] ?? 0
            const g = 対象材質.材質データ[i * 4 + 1] ?? 0
            const b = 対象材質.材質データ[i * 4 + 2] ?? 0
            const a = 対象材質.材質データ[i * 4 + 3] ?? 0
            assert.strictEqual(r + g + b + a, 255, `ベイク後の合計が255であるべき: 画素=${i}`)
        }
        const 中心岩 = 対象材質.材質データ[(8 * 解像度 + 8) * 4 + 2] ?? 0
        assert.ok(中心岩 > 0, '急勾配箇所の岩の重みが増加しているべき')
    })

    it('低地ベイクで標高の低い場所ほど泥の重みが増え、合計255が保たれること', () => {
        const 解像度 = 17
        const 一辺 = 32
        const 対象高さ場 = new 高さ場(解像度, 一辺)
        // 標高をx方向へ左(低)から右(高)へ-10m〜+10mの傾斜にする。
        for (let gz = 0; gz < 解像度; gz++) {
            for (let gx = 0; gx < 解像度; gx++) {
                対象高さ場.格子データ[gz * 解像度 + gx] = -10 + (gx / (解像度 - 1)) * 20
            }
        }
        const 対象材質 = new 地表材質(解像度, 一辺)
        対象材質.低地を泥へベイクする(対象高さ場)

        for (let i = 0; i < 解像度 * 解像度; i++) {
            const r = 対象材質.材質データ[i * 4 + 0] ?? 0
            const g = 対象材質.材質データ[i * 4 + 1] ?? 0
            const b = 対象材質.材質データ[i * 4 + 2] ?? 0
            const a = 対象材質.材質データ[i * 4 + 3] ?? 0
            assert.strictEqual(r + g + b + a, 255, `低地ベイク後の合計が255であるべき: 画素=${i}`)
        }
        const 中央行 = 8
        const 左端泥 = 対象材質.材質データ[(中央行 * 解像度 + 0) * 4 + 1] ?? 0
        const 右端泥 = 対象材質.材質データ[(中央行 * 解像度 + (解像度 - 1)) * 4 + 1] ?? 0
        assert.ok(左端泥 > 右端泥, '標高の低い側(左端)の泥の重みが高い側(右端)より大きいべき')
        assert.ok(左端泥 > 0, '標高の低い場所では泥の重みが0より大きいべき')
    })

    it('道路下ベイクで道路直下が泥100%になること', () => {
        const 対象材質 = new 地表材質(17, 32)
        対象材質.道路下を泥へベイクする([{
            制御点列: [
                { x: -10, y: 0, z: 0 },
                { x: 10, y: 0, z: 0 },
            ],
            全幅メートル: 4,
            散布除外バッファメートル: 8,
            細分割数: 20,
        }])
        const 中心泥 = 対象材質.材質データ[(8 * 17 + 8) * 4 + 1] ?? 0
        assert.strictEqual(中心泥, 255, '道路中心は泥100%(255)であるべき')
    })
})
