import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 散布 } from './散布.ts'
import type { チャンクの道路, 建物の配置 } from '../../../生成/編集資源契約.ts'

describe('散布編集モデル', () => {
    it('同一の乱数の種から常に完全に同一の散布結果が得られること', () => {
        const 設定 = { 最小間隔メートル: 8.0, 乱数の種: 1234567890123456789n }
        const 一辺 = 128

        const 結果1 = 散布.標本化を計算する(設定, 一辺, [], [])
        const 結果2 = 散布.標本化を計算する(設定, 一辺, [], [])

        assert.ok(結果1.length > 0, '散布結果が1点以上生成されるべき')
        assert.deepStrictEqual(結果1, 結果2, '同一の種から得られる散布結果は厳密に一致するべき')
    })

    it('異なる乱数の種からは異なる散布結果が得られること', () => {
        const 設定1 = { 最小間隔メートル: 8.0, 乱数の種: 100n }
        const 設定2 = { 最小間隔メートル: 8.0, 乱数の種: 200n }
        const 一辺 = 128

        const 結果1 = 散布.標本化を計算する(設定1, 一辺, [], [])
        const 結果2 = 散布.標本化を計算する(設定2, 一辺, [], [])

        assert.notDeepStrictEqual(結果1, 結果2, '異なる種からは異なる散布結果が得られるべき')
    })

    it('道路除外バッファおよび建物基礎周囲の点が除外されること', () => {
        const 設定 = { 最小間隔メートル: 4.0, 乱数の種: 99999n }
        const 一辺 = 128
        const 道路: チャンクの道路 = {
            制御点列: [
                { x: -50, y: 0, z: 0 },
                { x: 50, y: 0, z: 0 },
            ],
            全幅メートル: 6.0,
            散布除外バッファメートル: 10.0,
            細分割数: 30,
        }
        const 建物一覧: Array<建物の配置> = [
            {
                識別子: '家屋_1',
                種別: '家屋',
                位置: { x: 20, y: 0, z: 20 },
                向きラジアン: 0,
                基礎半径メートル: 8.0,
                なじみ半径メートル: 14.0,
            },
        ]

        const 結果 = 散布.標本化を計算する(設定, 一辺, [道路], 建物一覧)

        for (const 点 of 結果) {
            // 道路中心線 (z=0, x in [-50, 50]) 付近の除外検査
            if (点.x >= -45 && 点.x <= 45) {
                assert.ok(
                    Math.abs(点.z) >= 道路.散布除外バッファメートル - 0.5,
                    `道路除外バッファ内の点が除外されているべき: 点=(${点.x}, ${点.z})`,
                )
            }

            // 建物周囲 (距離 < 基礎半径+1.0 = 9.0) の除外検査
            const 建物距離 = Math.hypot(点.x - 20, 点.z - 20)
            assert.ok(建物距離 >= 9.0 - 0.1, `建物基礎周囲の点が除外されているべき: 距離=${建物距離}`)
        }
    })
})
