// 等高線から高さ場を生成するときに、同じ格子点へ異なる高さの拘束が重なった場合の型付きエラー。
// 呼び出し側は`見下ろし図のコマンドを積む.ts`の共通の捕まえ処理がmessageをそのまま操作帯へ出す。
// 衝突した2本の等高線の添字・格子点の座標・2つの高さをフィールドで持ち、読み手が現物の等高線を
// 直せる情報にする。参照: `_doc/設計/見下ろし図による地形編集.md`「判断3」。

// 0.1ミリメートル。高さはFloat32Arrayで保持するため、同じ拘束を表す2本の等高線でも
// float32への丸めと演算順序の違いで最下位ビット程度の差が出うる。この差だけを許容差として
// 吸収し、人が意図して描き分けた高さの違い(センチメートル単位以上)は必ず拒否する。格子の一辺
// (水平方向の解像度)には比例させない。格子が粗いほど大きな矛盾を飲み込む理由が無いためである。
export const 高さの一致とみなす許容差メートル = 0.0001

export class 等高線の拘束衝突 extends Error {
    public readonly 等高線の添字1: number
    public readonly 等高線の添字2: number
    public readonly 格子添字X: number
    public readonly 格子添字Z: number
    public readonly 高さメートル1: number
    public readonly 高さメートル2: number

    public constructor(
        等高線の添字1: number,
        等高線の添字2: number,
        格子添字X: number,
        格子添字Z: number,
        高さメートル1: number,
        高さメートル2: number,
    ) {
        super(
            `等高線${等高線の添字1}と等高線${等高線の添字2}が格子点(${格子添字X}, ${格子添字Z})で異なる高さを拘束している: ${高さメートル1}m と ${高さメートル2}m`,
        )
        this.name = '等高線の拘束衝突'
        this.等高線の添字1 = 等高線の添字1
        this.等高線の添字2 = 等高線の添字2
        this.格子添字X = 格子添字X
        this.格子添字Z = 格子添字Z
        this.高さメートル1 = 高さメートル1
        this.高さメートル2 = 高さメートル2
    }
}
