import type { 位置3次元 } from '../../../生成/編集資源契約.ts'

// 道路の帯の上をクリックしたときに、どの添字へ点を割り込ませるかと、その点の位置。
export interface 道路点の挿入先 {
    readonly 添字: number
    readonly 位置: 位置3次元
}

// 線分の上へ対象点を落とした足の位置を、線分の始点から終点までの比率で返す。
// 線分からはみ出す足は端へ丸めるため、返す比率は必ず0以上1以下になる。
function 線分へ落とした足の比率を求める(始点: 位置3次元, 終点: 位置3次元, 対象: 位置3次元): number {
    const 辺X = 終点.x - 始点.x
    const 辺Y = 終点.y - 始点.y
    const 辺Z = 終点.z - 始点.z
    const 辺の長さの2乗 = 辺X * 辺X + 辺Y * 辺Y + 辺Z * 辺Z
    if (辺の長さの2乗 <= 0) return 0
    const 内積 = (対象.x - 始点.x) * 辺X + (対象.y - 始点.y) * 辺Y + (対象.z - 始点.z) * 辺Z
    return Math.min(Math.max(内積 / 辺の長さの2乗, 0), 1)
}

// クリック点にいちばん近い区間を選び、その区間の上へ落とした足を挿入先として返す。
// 帯は制御点を通るなめらかな曲線に沿って張られるが、挿入先は制御点どうしを結ぶ直線で決める。
// 割り込ませた点がどの2点の間に入るかを利用者が見た目どおりに予想できるようにするためである。
// 区間が1つも無い(制御点が2つに満たない)ときはnullを返す。
export function 道路点の挿入先を求める(
    制御点列: readonly 位置3次元[],
    クリック点: 位置3次元,
): 道路点の挿入先 | null {
    let 挿入先: 道路点の挿入先 | null = null
    let 最短距離 = Number.POSITIVE_INFINITY
    for (let 区間の番号 = 0; 区間の番号 + 1 < 制御点列.length; 区間の番号++) {
        const 始点 = 制御点列[区間の番号]
        const 終点 = 制御点列[区間の番号 + 1]
        if (始点 === undefined || 終点 === undefined) continue
        const 比率 = 線分へ落とした足の比率を求める(始点, 終点, クリック点)
        const 位置: 位置3次元 = {
            x: 始点.x + (終点.x - 始点.x) * 比率,
            y: 始点.y + (終点.y - 始点.y) * 比率,
            z: 始点.z + (終点.z - 始点.z) * 比率,
        }
        const 距離 = Math.hypot(位置.x - クリック点.x, 位置.y - クリック点.y, 位置.z - クリック点.z)
        if (距離 < 最短距離) {
            最短距離 = 距離
            挿入先 = { 添字: 区間の番号 + 1, 位置 }
        }
    }
    return 挿入先
}
