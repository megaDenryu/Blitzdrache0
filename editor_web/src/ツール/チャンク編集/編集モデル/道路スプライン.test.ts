import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 道路スプライン } from './道路スプライン.ts'
import { 高さ場 } from './高さ場.ts'

describe('道路スプライン編集モデル', () => {
    it('制御点の追加・移動・削除が正しく機能すること', () => {
        const 道路 = new 道路スプライン({
            制御点列: [{ x: 0, y: 0, z: 0 }],
            全幅メートル: 8,
            散布除外バッファメートル: 14,
            細分割数: 20,
        })
        道路.点を追加する({ x: 10, y: 5, z: 10 })
        assert.strictEqual(道路.制御点列.length, 2)

        道路.点を移動する(1, { x: 20, y: 10, z: 20 })
        assert.deepStrictEqual(道路.制御点列[1], { x: 20, y: 10, z: 20 })

        const 削除点 = 道路.点を削除する(0)
        assert.deepStrictEqual(削除点, { x: 0, y: 0, z: 0 })
        assert.strictEqual(道路.制御点列.length, 1)
    })

    it('切土盛土で道路半幅内が道路高さになりなじみ帯が単調に補間されること', () => {
        const 解像度 = 65
        const 一辺 = 64
        const 対象高さ場 = new 高さ場(解像度, 一辺)
        const 道路標高 = 10.0
        const 道路 = new 道路スプライン({
            制御点列: [
                { x: -30, y: 道路標高, z: 0 },
                { x: 30, y: 道路標高, z: 0 },
            ],
            全幅メートル: 8, // 半幅 = 4m
            散布除外バッファメートル: 12, // なじみ帯 = 4m〜12m
            細分割数: 40,
        })

        道路.道路に合わせて切土盛土する(対象高さ場)

        // 道路中心 (z=0)
        const 中心高さ = 対象高さ場.標本高さを取得する(0, 0)
        assert.ok(Math.abs(中心高さ - 道路標高) < 1e-2, `道路中心は道路標高と一致するべき: 実際=${中心高さ}`)

        // 半幅内 (z=2)
        const 半幅内高さ = 対象高さ場.標本高さを取得する(0, 2)
        assert.ok(Math.abs(半幅内高さ - 道路標高) < 1e-2, `半幅内は道路標高と一致するべき: 実際=${半幅内高さ}`)

        // なじみ帯 (z=4 -> z=12) での単調性検査
        let 前の高さ = 道路標高
        for (let z = 5; z <= 11; z += 1) {
            const 現在の標高 = 対象高さ場.標本高さを取得する(0, z)
            assert.ok(
                現在の標高 <= 前の高さ,
                `なじみ帯は道路高さから元の地面高さ(0)へ単調減少するべき: z=${z}, 前=${前の高さ}, 現=${現在の標高}`,
            )
            前の高さ = 現在の標高
        }

        // なじみ帯外 (z=20)
        const 外側高さ = 対象高さ場.標本高さを取得する(0, 20)
        assert.strictEqual(外側高さ, 0, 'なじみ帯外は元の高さ0のままであるべき')
    })
})
