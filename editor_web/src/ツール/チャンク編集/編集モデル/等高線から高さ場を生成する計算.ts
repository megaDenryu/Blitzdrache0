import type { 等高線 } from '../../../生成/編集資源契約.ts'
import { 等高線を格子点へ固定する } from './等高線の格子点への固定.ts'

// 等高線一覧を拘束にして高さ格子を丸ごと作り直す純粋計算。等高線が通る格子点と外周の格子点を固定し、
// 残りの格子点を「4近傍の平均に等しい」という離散ラプラス方程式のガウス・ザイデル反復で解く。
// 外周を現在値で固定するのは、隣のチャンクとの縁の一致をこの生成が壊さないためである。
// 参照: `_doc/設計/見下ろし図による地形編集.md`「判断3」。

export const 収束とみなす最大変化メートル = 0.001
export const 反復回数の上限の解像度二乗に対する倍率 = 10

export function 等高線から高さ場を生成する(
    等高線一覧: ReadonlyArray<等高線>,
    解像度: number,
    一辺のメートル: number,
    現在の格子データ: Float32Array,
): Float32Array {
    if (等高線一覧.length === 0) {
        throw new Error('等高線が1本も無いため高さ場を生成できない')
    }
    if (現在の格子データ.length !== 解像度 * 解像度) {
        throw new Error(`格子データの要素数が解像度と合わない: 期待=${解像度 * 解像度}, 実際=${現在の格子データ.length}`)
    }
    const { 固定の印, 固定の高さ } = 等高線を格子点へ固定する(等高線一覧, 解像度, 一辺のメートル)
    const 結果 = new Float32Array(現在の格子データ)
    for (let i = 0; i < 結果.length; i++) {
        if (固定の印[i] === 1) 結果[i] = 固定の高さ[i] ?? 0
    }
    外周を固定する(固定の印, 解像度)
    ラプラス方程式を反復で解く(結果, 固定の印, 解像度)
    return 結果
}

function 外周を固定する(固定の印: Uint8Array, 解像度: number): void {
    for (let i = 0; i < 解像度; i++) {
        固定の印[i] = 1
        固定の印[(解像度 - 1) * 解像度 + i] = 1
        固定の印[i * 解像度] = 1
        固定の印[i * 解像度 + (解像度 - 1)] = 1
    }
}

// 固定されていない格子点を4近傍の平均へ置き換える反復。その場で更新するガウス・ザイデル法であり、
// 更新した値を同じ反復の中の後続の格子点がすぐ使うため、ヤコビ法より少ない反復で収束する。
function ラプラス方程式を反復で解く(格子: Float32Array, 固定の印: Uint8Array, 解像度: number): void {
    const 反復回数の上限 = 解像度 * 解像度 * 反復回数の上限の解像度二乗に対する倍率
    for (let 反復 = 0; 反復 < 反復回数の上限; 反復++) {
        let 最大変化 = 0
        for (let gz = 1; gz < 解像度 - 1; gz++) {
            for (let gx = 1; gx < 解像度 - 1; gx++) {
                const 添字 = gz * 解像度 + gx
                if (固定の印[添字] === 1) continue
                const 平均 = ((格子[添字 - 1] ?? 0) + (格子[添字 + 1] ?? 0) + (格子[添字 - 解像度] ?? 0) + (格子[添字 + 解像度] ?? 0)) / 4
                const 変化 = Math.abs(平均 - (格子[添字] ?? 0))
                if (変化 > 最大変化) 最大変化 = 変化
                格子[添字] = 平均
            }
        }
        if (最大変化 < 収束とみなす最大変化メートル) return
    }
}
