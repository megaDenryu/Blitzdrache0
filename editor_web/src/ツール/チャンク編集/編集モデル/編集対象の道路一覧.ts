import type { 位置3次元, 道路を追加する, 道路対象 } from '../../../生成/編集資源契約.ts'
import type { 道路の一覧 } from './道路の一覧.ts'
import type { 道路スプライン } from './道路スプライン.ts'
import type { 道路点の在り処 } from './道路点の在り処.ts'
import { 所属の道路一覧を取り出す, type 道路の所属 } from './道路対象の解決.ts'
import { チャンクの道路の既定の設定, 広域道路の既定の設定, type 道路の設定 } from './道路の既定の設定.ts'
import type { ワールド編集状態 } from './ワールド編集状態.ts'

// いま画面が編集している道路一覧を、編集モデルと所属をコンストラクタで受け取って保持する操作サービス。
// 画面のクリック・ドラッグの処理は道路が何本目かによって作用先が変わるため、道路対象の組み立てと
// 道路の取り出しをここへ集め、呼び出し側にモデルと所属を持ち回らせない。
export class 編集対象の道路一覧 {
    public constructor(
        private readonly _モデル: ワールド編集状態,
        private readonly _所属: 道路の所属,
    ) {}

    public get 一覧(): 道路の一覧 {
        return 所属の道路一覧を取り出す(this._モデル, this._所属)
    }

    public get 件数(): number {
        return this.一覧.件数
    }

    public 道路対象を作る(道路添字: number): 道路対象 {
        if (this._所属.種類 === '広域') return { 種類: '広域', 値: { 道路添字 } }
        return { 種類: 'チャンク', 値: { チャンク座標: { ...this._所属.チャンク座標 }, 道路添字 } }
    }

    public 道路を取り出す(道路添字: number): 道路スプライン {
        return this.一覧.道路を取り出す(道路添字)
    }

    // 道を1本足すコマンドを組み立てる。分岐のときは分かれ元の道路添字を渡して幅などを受け継ぎ、
    // まったく新しい道のときはnullを渡してこの所属の既定の設定から始める。
    public 道路を足すコマンドを作る(
        制御点列: ReadonlyArray<位置3次元>,
        設定を受け継ぐ道路添字: number | null,
    ): 道路を追加する {
        const 設定 = this._受け継ぐ設定を求める(設定を受け継ぐ道路添字)
        const 制御点の写し = 制御点列.map((点) => ({ x: 点.x, y: 点.y, z: 点.z }))
        if (this._所属.種類 === '広域') {
            return {
                種類: '広域',
                値: { 道路: { 制御点列: 制御点の写し, 全幅メートル: 設定.全幅メートル, 細分割数: 設定.細分割数 } },
            }
        }
        return {
            種類: 'チャンク',
            値: {
                チャンク座標: { ...this._所属.チャンク座標 },
                道路: { 制御点列: 制御点の写し, ...設定 },
            },
        }
    }

    // 在り処が指す制御点の位置を返す。道路も点も実在するときだけ値を返し、
    // 消えた点を指したままの在り処にはnullを返す。
    public 道路点の位置を求める(在り処: 道路点の在り処): 位置3次元 | null {
        const 一覧 = this.一覧
        if (!一覧.道路が在るか(在り処.道路添字)) return null
        return 一覧.道路を取り出す(在り処.道路添字).制御点列[在り処.制御点添字] ?? null
    }

    private _受け継ぐ設定を求める(設定を受け継ぐ道路添字: number | null): 道路の設定 {
        const 既定 = this._所属.種類 === '広域' ? 広域道路の既定の設定 : チャンクの道路の既定の設定
        if (設定を受け継ぐ道路添字 === null || !this.一覧.道路が在るか(設定を受け継ぐ道路添字)) return 既定
        const 見本 = this.一覧.道路を取り出す(設定を受け継ぐ道路添字)
        return {
            全幅メートル: 見本.全幅メートル,
            散布除外バッファメートル: 見本.散布除外バッファメートル,
            細分割数: 見本.細分割数,
        }
    }
}
