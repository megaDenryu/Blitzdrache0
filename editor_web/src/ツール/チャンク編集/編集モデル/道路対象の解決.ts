import type { 道路対象 } from '../../../生成/編集資源契約.ts'
import type { 道路スプライン } from './道路スプライン.ts'
import type { ワールド編集状態 } from './ワールド編集状態.ts'

// 道路対象が指している道路スプラインを編集状態から取り出す。
// 広域道路とチャンクの道路のどちらを指しているかの判別をここ1箇所へ閉じ、
// 操作コマンドの適用・差し戻し・画面のドラッグ処理が同じ分岐を書き写さないようにする。
export function 道路対象の道路スプラインを取り出す(状態: ワールド編集状態, 対象: 道路対象): 道路スプライン {
    if (対象.種類 === '広域') return 状態.広域道路
    return 状態.チャンクを取得する(対象.値).道路
}
