import type { チャンク座標, 道路対象 } from '../../../生成/編集資源契約.ts'
import type { 道路の一覧 } from './道路の一覧.ts'
import type { 道路スプライン } from './道路スプライン.ts'
import type { ワールド編集状態 } from './ワールド編集状態.ts'

// 道路の所属とは、道路一覧が大域世界のものか、あるチャンクのものかの区別のことである。
// 道路対象から道路添字を落としたものであり、一覧そのものを指すときに使う。
export type 道路の所属 = { readonly 種類: '広域' } | { readonly 種類: 'チャンク'; readonly チャンク座標: チャンク座標 }

export function 道路対象の所属を求める(対象: 道路対象): 道路の所属 {
    if (対象.種類 === '広域') return { 種類: '広域' }
    return { 種類: 'チャンク', チャンク座標: { ...対象.値.チャンク座標 } }
}

// 所属が指している道路一覧を編集状態から取り出す。広域道路とチャンクの道路のどちらを
// 指しているかの判別をここ1箇所へ閉じ、操作コマンドの適用・差し戻し・画面のドラッグ処理が
// 同じ分岐を書き写さないようにする。
export function 所属の道路一覧を取り出す(状態: ワールド編集状態, 所属: 道路の所属): 道路の一覧 {
    if (所属.種類 === '広域') return 状態.広域道路一覧
    return 状態.チャンクを取得する(所属.チャンク座標).道路一覧
}

export function 道路対象の道路一覧を取り出す(状態: ワールド編集状態, 対象: 道路対象): 道路の一覧 {
    return 所属の道路一覧を取り出す(状態, 道路対象の所属を求める(対象))
}

export function 道路対象の道路スプラインを取り出す(状態: ワールド編集状態, 対象: 道路対象): 道路スプライン {
    return 道路対象の道路一覧を取り出す(状態, 対象).道路を取り出す(対象.値.道路添字)
}
