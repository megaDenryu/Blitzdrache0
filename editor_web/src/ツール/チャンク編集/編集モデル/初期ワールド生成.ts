import type { 大域世界構造, チャンク構造, チャンク座標 } from '../../../生成/編集資源契約.ts'
import { ワールド編集状態 } from './ワールド編集状態.ts'
import { チャンク座標から乱数の種を作る } from './乱数.ts'
import { 初期地表材質データを生成する } from './初期地表材質生成.ts'
import { 座標から決定的な初期の高さを生成する } from './初期高さ生成.ts'

// 指定チャンク座標と大域構造に基づき決定的な初期チャンクと編集モデルを構築する。
// 大域から切り出した高さデータを受け取ったときは、座標を種にした合成でなくそれを高さの初期値にする。
// 座標を種にした合成は隣り合うチャンクの縁が一致せず、そのまま保存すると書き出しの縁の一致検査が
// 落ちるためである。地表材質のベイクと道路点の高さは、この初期値の上で導く。
export function 初期ワールド状態を生成する(
    座標: チャンク座標 = { x: 0, z: 0 },
    大域構造引数?: 大域世界構造,
    大域から切り出した高さデータ?: Float32Array,
): ワールド編集状態 {
    const 大域構造: 大域世界構造 = 大域構造引数 ?? {
        区画割り: {
            一辺のメートル: 1024,
            軸あたりチャンク数: 4,
            チャンクあたり格子解像度: 128,
        },
        広域道路一覧: [{
            制御点列: [],
            全幅メートル: 8.0,
            細分割数: 80,
        }],
    }

    const 状態 = new ワールド編集状態(大域構造)
    const 頂点数 = 大域構造.区画割り.チャンクあたり格子解像度 + 1
    const チャンク一辺 = 大域構造.区画割り.一辺のメートル / 大域構造.区画割り.軸あたりチャンク数

    const 高さデータ = 大域から切り出した高さデータ ?? 座標から決定的な初期の高さを生成する(頂点数, チャンク一辺, 座標)

    const 材質データ = 初期地表材質データを生成する(頂点数, 座標)
    const 乱数種 = チャンク座標から乱数の種を作る(座標, 12345n)

    const チャンク構造設定: チャンク構造 = {
        道路一覧: [{
            制御点列: [
                { x: -80, y: 0, z: -60 },
                { x: -30, y: 0, z: -20 },
                { x: 20, y: 0, z: 20 },
                { x: 75, y: 0, z: 70 },
            ],
            全幅メートル: 8.0,
            散布除外バッファメートル: 14.0,
            細分割数: 80,
        }],
        建物一覧: [],
        散布: {
            最小間隔メートル: 5.5,
            乱数の種: 乱数種,
        },
        // 個体一覧は散布の設定から導く派生であり、チャンク編集状態が保存のたびに導き直す。
        // 初期生成は設定だけを与え、空の列から始める。
        散布の個体一覧: [],
    }

    const チャンク = 状態.チャンクを登録する(座標, チャンク構造設定, 高さデータ, 材質データ)
    // 低地の泥寄せを先に重ね、崖の底が低地であっても急勾配ベイクが岩肌へ上書きできるようにする。
    チャンク.地表材質.低地を泥へベイクする(チャンク.高さ場)
    チャンク.地表材質.急勾配を岩肌へベイクする(チャンク.高さ場)
    for (const 道路 of チャンク.道路一覧.全ての道路) {
        for (const 点 of 道路.制御点列) {
            点.y = チャンク.高さ場.標本高さを取得する(点.x, 点.z)
        }
    }

    状態.選択中チャンク座標 = 座標
    return 状態
}
