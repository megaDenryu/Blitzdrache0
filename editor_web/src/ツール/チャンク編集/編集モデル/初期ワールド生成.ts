import type { 大域世界構造, チャンク構造, チャンク座標 } from '../../../生成/編集資源契約.ts'
import { ワールド編集状態 } from './ワールド編集状態.ts'
import { チャンク座標から乱数の種を作る } from './乱数.ts'
import { 初期地表材質データを生成する } from './初期地表材質生成.ts'

// 指定チャンク座標と大域構造に基づき決定的な初期チャンクと編集モデルを構築する。
export function 初期ワールド状態を生成する(
    座標: チャンク座標 = { x: 0, z: 0 },
    大域構造引数?: 大域世界構造,
): ワールド編集状態 {
    const 大域構造: 大域世界構造 = 大域構造引数 ?? {
        区画割り: {
            一辺のメートル: 1024,
            軸あたりチャンク数: 4,
            チャンクあたり格子解像度: 128,
        },
        広域道路: {
            制御点列: [],
            全幅メートル: 8.0,
            細分割数: 80,
        },
    }

    const 状態 = new ワールド編集状態(大域構造)
    const 頂点数 = 大域構造.区画割り.チャンクあたり格子解像度 + 1
    const チャンク一辺 = 大域構造.区画割り.一辺のメートル / 大域構造.区画割り.軸あたりチャンク数
    const 格子間隔 = チャンク一辺 / (頂点数 - 1)
    const 半分 = チャンク一辺 / 2

    const 高さデータ = new Float32Array(頂点数 * 頂点数)

    for (let gz = 0; gz < 頂点数; gz++) {
        for (let gx = 0; gx < 頂点数; gx++) {
            const wx = 座標.x * チャンク一辺 + (gx * 格子間隔 - 半分)
            const wz = 座標.z * チャンク一辺 + (gz * 格子間隔 - 半分)

            let h = Math.sin(wx * 0.02) * Math.cos(wz * 0.02) * 8.0
            h += Math.sin(wx * 0.05 + 1.2) * Math.sin(wz * 0.05) * 3.0
            h += Math.sin(wx * 0.1) * Math.cos(wz * 0.1) * 0.8

            高さデータ[gz * 頂点数 + gx] = h
        }
    }

    const 材質データ = 初期地表材質データを生成する(頂点数, 座標)
    const 乱数種 = チャンク座標から乱数の種を作る(座標, 12345n)

    const チャンク構造設定: チャンク構造 = {
        道路: {
            制御点列: [
                { x: -80, y: 0, z: -60 },
                { x: -30, y: 0, z: -20 },
                { x: 20, y: 0, z: 20 },
                { x: 75, y: 0, z: 70 },
            ],
            全幅メートル: 8.0,
            散布除外バッファメートル: 14.0,
            細分割数: 80,
        },
        建物一覧: [],
        散布: {
            最小間隔メートル: 5.5,
            乱数の種: 乱数種,
        },
    }

    const チャンク = 状態.チャンクを登録する(座標, チャンク構造設定, 高さデータ, 材質データ)
    // 低地の泥寄せを先に重ね、崖の底が低地であっても急勾配ベイクが岩肌へ上書きできるようにする。
    チャンク.地表材質.低地を泥へベイクする(チャンク.高さ場)
    チャンク.地表材質.急勾配を岩肌へベイクする(チャンク.高さ場)
    for (let i = 0; i < チャンク.道路.制御点列.length; i++) {
        const 点 = チャンク.道路.制御点列[i]
        if (点 !== undefined) {
            点.y = チャンク.高さ場.標本高さを取得する(点.x, 点.z)
        }
    }

    状態.選択中チャンク座標 = 座標
    return 状態
}
