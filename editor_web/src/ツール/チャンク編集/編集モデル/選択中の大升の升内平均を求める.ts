import type { 地表材質層 } from '../../../生成/編集資源契約.ts'
import { 大升の分割を求める, type 大升の分割 } from './大升の格子分割.ts'
import { 地表材質層の数, 添字を地表材質層に変換する } from './地表材質層の添字.ts'

export interface 大升1つの升内平均 {
    readonly 高さ平均メートル: number
    readonly 重みが最大の層: 地表材質層
}

// 見下ろし図のインスペクターが選択中の大升1つだけの現在の高さ場・材質重みを読むための計算。
// 大升の格子分割.tsの升内平均はチャンク全体を走査するが、選択の表示はその1升だけで足りるため、
// その升に含まれる格子点だけを走査する軽い計算にする。
export function 選択中の大升の升内平均を求める(
    解像度: number,
    格子データ: Float32Array,
    材質データ: Uint8Array,
    一辺の升目数: number,
    列: number,
    行: number,
): 大升1つの升内平均 {
    const 分割: 大升の分割 = 大升の分割を求める(解像度, 一辺の升目数)
    if (列 < 0 || 行 < 0 || 列 >= 分割.軸あたり大升数 || 行 >= 分割.軸あたり大升数) {
        throw new Error(`大升の(列,行)が範囲外: (${列},${行}), 軸あたり大升数=${分割.軸あたり大升数}`)
    }
    let 高さ合計 = 0
    const 重み合計 = new Float64Array(地表材質層の数)
    const 点の数 = (一辺の升目数 + 1) * (一辺の升目数 + 1)
    for (let dz = 0; dz <= 一辺の升目数; dz++) {
        for (let dx = 0; dx <= 一辺の升目数; dx++) {
            const 格子添字 = (行 * 一辺の升目数 + dz) * 解像度 + (列 * 一辺の升目数 + dx)
            高さ合計 += 格子データ[格子添字] ?? 0
            for (let 層 = 0; 層 < 地表材質層の数; 層++) {
                重み合計[層] = (重み合計[層] ?? 0) + (材質データ[格子添字 * 地表材質層の数 + 層] ?? 0)
            }
        }
    }
    let 最大の層 = 0
    for (let 層 = 1; 層 < 地表材質層の数; 層++) {
        if ((重み合計[層] ?? 0) > (重み合計[最大の層] ?? 0)) 最大の層 = 層
    }
    return { 高さ平均メートル: 高さ合計 / 点の数, 重みが最大の層: 添字を地表材質層に変換する(最大の層) }
}
