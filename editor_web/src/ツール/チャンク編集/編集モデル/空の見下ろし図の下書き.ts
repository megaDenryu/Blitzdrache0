import type { 見下ろし図の下書き } from '../../../生成/編集資源契約.ts'

// 粗マスの一辺の既定は8升目。2メートル刻みの格子なら16メートルの粗マスになる。
// 参照: `_doc/設計/見下ろし図による地形編集.md`「判断4」。
export const 粗マスの一辺の升目数の既定 = 8

// 等高線も粗マスの塗りも持たない下書き。初期生成のチャンクと、下書きを持たない旧版の保存物の読み替えに使う。
export function 空の見下ろし図の下書き(): 見下ろし図の下書き {
    return { 等高線一覧: [], 粗マスの一辺の升目数: 粗マスの一辺の升目数の既定, 粗マスの塗り一覧: [] }
}
