import type { チャンク座標, チャンク構造, 粗マスの塗り, 散布の個体, 散布の設定 } from '../../../生成/編集資源契約.ts'
import { 粗マスから地形を生成する as 粗マスから地形を計算する } from './粗マスから地形を生成する計算.ts'
import { 散布 } from './散布.ts'
import { 選択中の粗マスの升内平均を求める as 選択中の粗マスの升内平均を計算する, type 粗マス1つの升内平均 } from './選択中の粗マスの升内平均を求める.ts'
import { 道路の一覧 } from './道路の一覧.ts'
import { 建物の管理 } from './建物.ts'
import { 高さ場から粗マスを導く as 高さ場から粗マスを計算する } from './高さ場から粗マスを導く計算.ts'
import { 高さ場 } from './高さ場.ts'
import { 地表材質 } from './地表材質.ts'
import { 見下ろし図の下書きの管理 } from './見下ろし図の下書きの管理.ts'
import type { 下書きと正本の揃い } from './下書きと正本の揃い.ts'

// 単一チャンク内の地形高さ・地表材質・道路一覧・建物・散布・見下ろし図の下書きの各モデルを保持する。
// 下書きと正本の揃いは保存物に無く、読み込み直後は下書きと正本のどちらが新しいか判断できないため「未確認」から始める。
export class チャンク編集状態 {
    public readonly 座標: チャンク座標
    public readonly 道路一覧: 道路の一覧
    public readonly 建物: 建物の管理
    public 散布: 散布の設定
    public readonly 高さ場: 高さ場
    public readonly 地表材質: 地表材質
    public readonly 下書き: 見下ろし図の下書きの管理
    public 下書きと正本の揃い: 下書きと正本の揃い = '未確認'

    public constructor(
        座標: チャンク座標,
        構造: チャンク構造,
        一辺のメートル: number,
        格子解像度: number,
        初期高さデータ?: Float32Array,
        初期材質データ?: Uint8Array,
    ) {
        this.座標 = { x: 座標.x, z: 座標.z }
        this.道路一覧 = new 道路の一覧(構造.道路一覧)
        this.建物 = new 建物の管理(構造.建物一覧)
        this.散布 = { 最小間隔メートル: 構造.散布.最小間隔メートル, 乱数の種: 構造.散布.乱数の種 }
        this.高さ場 = new 高さ場(格子解像度, 一辺のメートル, 初期高さデータ)
        this.地表材質 = new 地表材質(格子解像度, 一辺のメートル, 初期材質データ)
        this.下書き = new 見下ろし図の下書きの管理(構造.見下ろし図の下書き)
    }

    // 散布の個体一覧を設定から導き直す。読み込んだ保存物の個体一覧を使わないのは、個体の列が
    // 設定・道路・建物から決まる派生であり、保存物は焼く側へ渡すための写しだからである。
    // 保存のたびに導き直すことで、道路や建物を動かした後の保存物が古い木の列を運ぶことがなくなる。
    public 散布の個体一覧を導く(): Array<散布の個体> {
        return 散布.個体一覧を確定する(
            this.座標,
            this.散布,
            this.高さ場.一辺のメートル,
            this.道路一覧.チャンクの道路一覧として取り出す(),
            this.建物.一覧を取得する(),
        )
    }

    // 粗マスの塗りから高さ場と地表材質を同時に作り直す(見下ろし図の設計正本の判断4)。
    public 粗マスから地形を生成し直す(塗り一覧: ReadonlyArray<粗マスの塗り>, 一辺の升目数: number): void {
        const 生成した地形 = 粗マスから地形を計算する(塗り一覧, 一辺の升目数, this.高さ場.解像度, this.高さ場.格子データ, this.地表材質.材質データ)
        this.高さ場.格子データを置き換える(生成した地形.高さ)
        this.地表材質.材質データを置き換える(生成した地形.材質)
    }

    // 高さ場と地表材質から粗マスの塗りを導く(見下ろし図の設計正本の判断5)。
    public 高さ場から粗マスを導く(一辺の升目数: number): Array<粗マスの塗り> {
        return 高さ場から粗マスを計算する(一辺の升目数, this.高さ場.解像度, this.高さ場.格子データ, this.地表材質.材質データ)
    }

    // 選択中の粗マス1つだけの現在の高さ場・材質重みの升内平均を求める(見下ろし図の右サイドバーの表示用)。
    public 選択中の粗マスの升内平均を求める(一辺の升目数: number, 列: number, 行: number): 粗マス1つの升内平均 {
        return 選択中の粗マスの升内平均を計算する(this.高さ場.解像度, this.高さ場.格子データ, this.地表材質.材質データ, 一辺の升目数, 列, 行)
    }

    public 構造を取得する(): チャンク構造 {
        return {
            道路一覧: this.道路一覧.チャンクの道路一覧として取り出す(),
            建物一覧: this.建物.一覧を取得する(),
            散布: { ...this.散布 },
            散布の個体一覧: this.散布の個体一覧を導く(),
            見下ろし図の下書き: this.下書き.契約の形で取り出す(),
        }
    }
}
