import { 地表材質層の数 } from './地表材質層の添字.ts'

// 高さ格子を大升へ区切る分割と、大升ごとの升内平均。大升から地形を生成する計算(塗っていない大升の
// 制御点の値)と、高さ場から大升を導く計算(全ての大升の塗り)の両方が同じ平均を使う。
// 大升の一辺はチャンクあたり格子解像度(升目の数 = 格子点の数 - 1)を割り切る値だけを受け付ける。
// 参照: `_doc/設計/見下ろし図による地形編集.md`「判断4」「判断5」。

export type 大升の分割 = {
    readonly 一辺の升目数: number
    readonly 軸あたり大升数: number
}

export function 大升の分割を求める(解像度: number, 一辺の升目数: number): 大升の分割 {
    const 升目数 = 解像度 - 1
    if (!Number.isInteger(一辺の升目数) || 一辺の升目数 < 1 || 升目数 % 一辺の升目数 !== 0) {
        throw new Error(`大升の一辺の升目数が格子の升目数を割り切らない: 一辺=${一辺の升目数}, 升目数=${升目数}`)
    }
    return { 一辺の升目数, 軸あたり大升数: 升目数 / 一辺の升目数 }
}

// 大升(列,行)に含まれる格子点は、列*一辺 から (列+1)*一辺 までの両端を含む(一辺+1)^2個である。
// 隣の大升と縁の格子点を共有するが、平均の目的では境界の点をどちらにも数えて差し支えない。
export type 大升ごとの升内平均 = {
    readonly 高さ平均: Float64Array
    readonly 重み平均: Float64Array
}

export function 大升ごとの升内平均を求める(
    分割: 大升の分割,
    解像度: number,
    格子データ: Float32Array,
    材質データ: Uint8Array,
): 大升ごとの升内平均 {
    const 大升の総数 = 分割.軸あたり大升数 * 分割.軸あたり大升数
    const 高さ平均 = new Float64Array(大升の総数)
    const 重み平均 = new Float64Array(大升の総数 * 地表材質層の数)
    const 点の数 = (分割.一辺の升目数 + 1) * (分割.一辺の升目数 + 1)
    for (let 行 = 0; 行 < 分割.軸あたり大升数; 行++) {
        for (let 列 = 0; 列 < 分割.軸あたり大升数; 列++) {
            const 大升添字 = 行 * 分割.軸あたり大升数 + 列
            for (let dz = 0; dz <= 分割.一辺の升目数; dz++) {
                for (let dx = 0; dx <= 分割.一辺の升目数; dx++) {
                    const 格子添字 = (行 * 分割.一辺の升目数 + dz) * 解像度 + (列 * 分割.一辺の升目数 + dx)
                    高さ平均[大升添字] += 格子データ[格子添字] ?? 0
                    for (let 層 = 0; 層 < 地表材質層の数; 層++) {
                        重み平均[大升添字 * 地表材質層の数 + 層] += 材質データ[格子添字 * 地表材質層の数 + 層] ?? 0
                    }
                }
            }
            高さ平均[大升添字] /= 点の数
            for (let 層 = 0; 層 < 地表材質層の数; 層++) 重み平均[大升添字 * 地表材質層の数 + 層] /= 点の数
        }
    }
    return { 高さ平均, 重み平均 }
}

export function 大升の添字を求める(分割: 大升の分割, 列: number, 行: number): number {
    if (!Number.isInteger(列) || !Number.isInteger(行) || 列 < 0 || 行 < 0 || 列 >= 分割.軸あたり大升数 || 行 >= 分割.軸あたり大升数) {
        throw new Error(`大升の(列,行)が範囲外: (${列},${行}), 軸あたり大升数=${分割.軸あたり大升数}`)
    }
    return 行 * 分割.軸あたり大升数 + 列
}
