import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import type { 等高線 } from '../../../生成/編集資源契約.ts'
import { 見下ろし図の下書きの管理 } from './見下ろし図の下書きの管理.ts'
import { 空の見下ろし図の下書き } from './空の見下ろし図の下書き.ts'

const 線A: 等高線 = { 高さメートル: 4, 頂点列: [{ x: 0, z: 0 }, { x: 10, z: 0 }], 閉じている: false }
const 線B: 等高線 = { 高さメートル: 8, 頂点列: [{ x: 0, z: 0 }, { x: 10, z: 0 }, { x: 10, z: 10 }], 閉じている: true }

describe('見下ろし図の下書きの管理', () => {
    it('等高線の追加・変更・削除・挿入が変更前を返しながら動くこと', () => {
        const 管理 = new 見下ろし図の下書きの管理(空の見下ろし図の下書き())
        assert.strictEqual(管理.等高線を追加する(線A), 0)
        assert.strictEqual(管理.等高線を追加する(線B), 1)
        const 変更前 = 管理.等高線を変更する(0, { ...線A, 高さメートル: 5 })
        assert.deepStrictEqual(変更前, 線A)
        assert.strictEqual(管理.等高線一覧を取得する()[0]?.高さメートル, 5)
        const 削除 = 管理.等高線を削除する(0)
        assert.strictEqual(削除.高さメートル, 5)
        assert.deepStrictEqual(管理.等高線一覧を取得する(), [線B])
        管理.等高線を添字へ挿入する(0, 線A)
        assert.deepStrictEqual(管理.等高線一覧を取得する(), [線A, 線B])
        assert.throws(() => 管理.等高線を削除する(2), /範囲外/)
        assert.throws(() => 管理.等高線を変更する(-1, 線A), /範囲外/)
    })

    it('取り出した等高線を書き換えても保持している下書きが変わらないこと', () => {
        const 管理 = new 見下ろし図の下書きの管理(空の見下ろし図の下書き())
        管理.等高線を追加する(線A)
        const 取り出し = 管理.等高線一覧を取得する()
        取り出し[0]?.頂点列.push({ x: 99, z: 99 })
        assert.strictEqual(管理.等高線一覧を取得する()[0]?.頂点列.length, 2)
    })

    it('大升を塗ると同じ升は上書きされ、高さも層も無い項目は塗りを消すこと', () => {
        const 管理 = new 見下ろし図の下書きの管理(空の見下ろし図の下書き())
        管理.大升を塗る(8, [{ 列: 1, 行: 2, 高さメートル: 3, 層: '岩' }, { 列: 0, 行: 0, 高さメートル: null, 層: '砂' }])
        管理.大升を塗る(8, [{ 列: 1, 行: 2, 高さメートル: 6, 層: null }])
        assert.deepStrictEqual(管理.大升の塗り一覧を取得する(), [
            { 列: 0, 行: 0, 高さメートル: null, 層: '砂' },
            { 列: 1, 行: 2, 高さメートル: 6, 層: null },
        ])
        管理.大升を塗る(8, [{ 列: 0, 行: 0, 高さメートル: null, 層: null }])
        assert.deepStrictEqual(管理.大升の塗り一覧を取得する(), [{ 列: 1, 行: 2, 高さメートル: 6, 層: null }])
    })

    it('一辺が変わると塗りを空にしてから置くこと', () => {
        const 管理 = new 見下ろし図の下書きの管理(空の見下ろし図の下書き())
        管理.大升を塗る(8, [{ 列: 1, 行: 2, 高さメートル: 3, 層: '岩' }])
        管理.大升を塗る(4, [{ 列: 5, 行: 5, 高さメートル: 1, 層: null }])
        assert.strictEqual(管理.大升の一辺の升目数を取得する(), 4)
        assert.deepStrictEqual(管理.大升の塗り一覧を取得する(), [{ 列: 5, 行: 5, 高さメートル: 1, 層: null }])
        assert.throws(() => 管理.大升を塗る(0, []), /正の整数/)
    })

    it('契約の形で取り出した下書きから同じ下書きを組み直せること', () => {
        const 管理 = new 見下ろし図の下書きの管理(空の見下ろし図の下書き())
        管理.等高線を追加する(線B)
        管理.大升を塗る(8, [{ 列: 1, 行: 2, 高さメートル: 3, 層: '岩' }])
        const 契約 = 管理.契約の形で取り出す()
        const 組み直し = new 見下ろし図の下書きの管理(契約)
        assert.deepStrictEqual(組み直し.契約の形で取り出す(), 契約)
        assert.deepStrictEqual(契約, {
            等高線一覧: [線B],
            大升の一辺の升目数: 8,
            大升の塗り一覧: [{ 列: 1, 行: 2, 高さメートル: 3, 層: '岩' }],
        })
    })
})
