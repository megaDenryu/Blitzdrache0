import type { チャンク座標 } from '../../../生成/編集資源契約.ts'

// チャンク座標とチャンクの寸法から、決定的な初期の高さ格子を合成する。同一のチャンク座標からは
// 常に同一の結果になる。これが使われるのは大域のマザーハイトマップがまだ保存されていない間だけであり、
// 大域が保存済みのときの初期値はサーバーが大域から切り出したものになる(編集サーバーの
// `chunk_height_supply`が担う)。座標ごとに独立した合成であるため、隣り合うチャンクの縁は一致しない。
export function 座標から決定的な初期の高さを生成する(
    頂点数: number,
    チャンク一辺のメートル: number,
    座標: チャンク座標,
): Float32Array {
    const 格子間隔 = チャンク一辺のメートル / (頂点数 - 1)
    const 半分 = チャンク一辺のメートル / 2
    const 高さデータ = new Float32Array(頂点数 * 頂点数)

    for (let gz = 0; gz < 頂点数; gz++) {
        for (let gx = 0; gx < 頂点数; gx++) {
            const wx = 座標.x * チャンク一辺のメートル + (gx * 格子間隔 - 半分)
            const wz = 座標.z * チャンク一辺のメートル + (gz * 格子間隔 - 半分)

            let h = Math.sin(wx * 0.02) * Math.cos(wz * 0.02) * 8.0
            h += Math.sin(wx * 0.05 + 1.2) * Math.sin(wz * 0.05) * 3.0
            h += Math.sin(wx * 0.1) * Math.cos(wz * 0.1) * 0.8

            高さデータ[gz * 頂点数 + gx] = h
        }
    }
    return 高さデータ
}
