import type { チャンク座標 } from '../../../生成/編集資源契約.ts'
import { チャンク座標から乱数の種を作る, 決定的乱数生成器 } from './乱数.ts'
import { 合計255へ正規化する } from './地表材質正規化.ts'

// 初期チャンク生成の材質ノイズに使う塩(散布の乱数種12345nと系列を分けるための定数)。
const 材質ノイズの塩 = 987654321n
// 低周波ノイズが泥の重みへ混ぜ込む最大比率。「草の重みを泥へ少し混ぜる程度」に留める。
const ノイズ由来泥重み上限 = 0.12
// 低周波ノイズ場を構成する粗グリッドの一辺の格子数。この数の格子点間を双線形補間して
// 全体解像度へ引き伸ばし、画素ごとの白色ノイズではなく滑らかな濃淡にする(値ノイズ)。
const 粗グリッド分割数 = 4

// 粗い格子点だけへ乱数を振り、双線形補間で全体解像度へ引き伸ばして低周波の濃淡場を作る。
function 低周波ノイズ場を生成する(頂点数: number, 生成器: 決定的乱数生成器): Float64Array {
    const 粗グリッド一辺 = 粗グリッド分割数 + 1
    const 粗グリッド = new Float64Array(粗グリッド一辺 * 粗グリッド一辺)
    for (let i = 0; i < 粗グリッド.length; i++) {
        粗グリッド[i] = 生成器.次の実数を生成する()
    }

    const 結果 = new Float64Array(頂点数 * 頂点数)
    for (let gz = 0; gz < 頂点数; gz++) {
        for (let gx = 0; gx < 頂点数; gx++) {
            const fx = (gx / (頂点数 - 1)) * 粗グリッド分割数
            const fz = (gz / (頂点数 - 1)) * 粗グリッド分割数
            const x0 = Math.min(Math.floor(fx), 粗グリッド分割数 - 1)
            const z0 = Math.min(Math.floor(fz), 粗グリッド分割数 - 1)
            const tx = fx - x0
            const tz = fz - z0
            const v00 = 粗グリッド[z0 * 粗グリッド一辺 + x0] ?? 0
            const v10 = 粗グリッド[z0 * 粗グリッド一辺 + (x0 + 1)] ?? 0
            const v01 = 粗グリッド[(z0 + 1) * 粗グリッド一辺 + x0] ?? 0
            const v11 = 粗グリッド[(z0 + 1) * 粗グリッド一辺 + (x0 + 1)] ?? 0
            結果[gz * 頂点数 + gx] =
                (1 - tx) * (1 - tz) * v00 + tx * (1 - tz) * v10 + (1 - tx) * tz * v01 + tx * tz * v11
        }
    }
    return 結果
}

// チャンク座標から、決定的な初期地表材質(草・泥のみの濃淡。岩・砂は0)のバイト列を合成する。
// 同一のチャンク座標からは常に同一の結果になる。低地の泥寄せ・急勾配の岩肌ベイクは、
// このデータを地表材質へ登録した後、地表材質のメソッドとして別途重ねる。
export function 初期地表材質データを生成する(頂点数: number, 座標: チャンク座標): Uint8Array {
    const 種 = チャンク座標から乱数の種を作る(座標, 材質ノイズの塩)
    const ノイズ場 = 低周波ノイズ場を生成する(頂点数, new 決定的乱数生成器(種))
    const 材質データ = new Uint8Array(頂点数 * 頂点数 * 4)

    for (let i = 0; i < 頂点数 * 頂点数; i++) {
        const 泥比率 = (ノイズ場[i] ?? 0) * ノイズ由来泥重み上限
        const 草 = Math.floor((1 - 泥比率) * 255)
        const 泥 = Math.floor(泥比率 * 255)
        const [r, g, b, a] = 合計255へ正規化する(草, 泥, 0, 0)
        材質データ[i * 4 + 0] = r
        材質データ[i * 4 + 1] = g
        材質データ[i * 4 + 2] = b
        材質データ[i * 4 + 3] = a
    }
    return 材質データ
}
