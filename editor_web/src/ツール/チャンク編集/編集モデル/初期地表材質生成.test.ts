import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 初期地表材質データを生成する } from './初期地表材質生成.ts'

describe('初期地表材質生成', () => {
    it('同一チャンク座標からは常に完全に同一の材質データが得られること', () => {
        const 座標 = { x: 3, z: -2 }
        const データA = 初期地表材質データを生成する(17, 座標)
        const データB = 初期地表材質データを生成する(17, 座標)
        assert.deepStrictEqual(データA, データB, '同一座標では材質データが完全に一致すること')
    })

    it('異なるチャンク座標からは異なる材質データが得られること', () => {
        const データ1 = 初期地表材質データを生成する(17, { x: 0, z: 0 })
        const データ2 = 初期地表材質データを生成する(17, { x: 5, z: 5 })
        assert.notDeepStrictEqual(データ1, データ2, '異なる座標では材質データが異なること')
    })

    it('全画素の合計が厳密に255であること', () => {
        const データ = 初期地表材質データを生成する(17, { x: 1, z: 1 })
        for (let i = 0; i < 17 * 17; i++) {
            const 合計 = (データ[i * 4 + 0] ?? 0) + (データ[i * 4 + 1] ?? 0) + (データ[i * 4 + 2] ?? 0) + (データ[i * 4 + 3] ?? 0)
            assert.strictEqual(合計, 255, `画素 ${i} の合計が255であるべき`)
        }
    })

    it('低周波ノイズにより泥の重みが画素間で変化し、単色のべた塗りにならないこと', () => {
        const データ = 初期地表材質データを生成する(17, { x: 2, z: -1 })
        const 泥重み一覧 = new Set<number>()
        for (let i = 0; i < 17 * 17; i++) {
            泥重み一覧.add(データ[i * 4 + 1] ?? 0)
        }
        assert.ok(泥重み一覧.size > 1, '泥の重みが画素間で複数の値を取るべき(単色のべた塗りではない)')
    })

    it('岩・砂は常に0であること(急勾配・低地の重ねベイクは別工程が担う)', () => {
        const データ = 初期地表材質データを生成する(17, { x: 0, z: 0 })
        for (let i = 0; i < 17 * 17; i++) {
            assert.strictEqual(データ[i * 4 + 2] ?? 0, 0, `画素 ${i} の岩は0であるべき`)
            assert.strictEqual(データ[i * 4 + 3] ?? 0, 0, `画素 ${i} の砂は0であるべき`)
        }
    })
})
