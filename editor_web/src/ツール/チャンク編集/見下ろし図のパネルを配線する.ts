import type { 地表材質層 } from '../../生成/編集資源契約.ts'
import type { 見下ろし図の下書きの管理 } from './編集モデル/index.ts'
import type { チャンク編集画面部品 } from './画面/index.ts'
import type { チャンク編集状態 } from './チャンク編集状態.ts'
import type { コマンドを積む関数 } from './見下ろし図のコマンドを積む.ts'

// 右サイドバーの等高線パネルと大升パネルの出来事を、画面の編集状態の書き換えとコマンドの積み方へ結ぶ。
// 数値の欄は入力が決まったときだけ知らせてくるため、ここで1回の知らせを1つのコマンドにする。
export function 見下ろし図のパネルを配線する(
    部品: チャンク編集画面部品,
    状態: チャンク編集状態,
    積む: コマンドを積む関数,
    下書きを読む: () => 見下ろし図の下書きの管理,
): void {
    const 見下ろし図 = 状態.見下ろし図
    const チャンク座標 = (): { x: number; z: number } => ({ ...状態.対象チャンク座標 })
    // 選んだ大升の高さ・層だけを差し替えて塗り直す。片方だけ変えても、もう片方の既存の塗りは残す。
    const 選択中の大升を1升だけ塗る = (差し替え: { 高さメートル?: number | null; 層?: 地表材質層 | null }): void => {
        const 番地 = 見下ろし図.選択中の大升の番地
        if (番地 === null) return
        const 既存 = 下書きを読む().大升の塗り一覧を取得する().find((塗り) => 塗り.列 === 番地.列 && 塗り.行 === 番地.行)
        積む({
            種類: '大升を塗る',
            値: {
                チャンク座標: チャンク座標(),
                大升の一辺の升目数: 下書きを読む().大升の一辺の升目数を取得する(),
                塗り一覧: [{
                    列: 番地.列,
                    行: 番地.行,
                    高さメートル: '高さメートル' in 差し替え ? (差し替え.高さメートル ?? null) : (既存?.高さメートル ?? null),
                    層: '層' in 差し替え ? (差し替え.層 ?? null) : (既存?.層 ?? null),
                }],
            },
        })
    }

    部品.インスペクター.部品.等高線.配線する({
        on選んだ線の高さ確定: (高さメートル) => {
            const 添字 = 見下ろし図.選択中の等高線の添字
            if (添字 === null) return
            const 線 = 下書きを読む().等高線一覧を取得する()[添字]
            if (線 === undefined) return
            積む({ 種類: '等高線を変更する', 値: { チャンク座標: チャンク座標(), 添字, 等高線: { ...線, 高さメートル } } })
        },
        on選んだ線を削除する: () => {
            const 添字 = 見下ろし図.選択中の等高線の添字
            if (添字 === null) return
            見下ろし図.選択中の等高線の添字 = null
            積む({ 種類: '等高線を削除する', 値: { チャンク座標: チャンク座標(), 添字 } })
        },
        on新しい線の高さ確定: (高さメートル) => { 見下ろし図.新しい等高線の高さメートル = 高さメートル },
        on導く間隔確定: (間隔メートル) => { 見下ろし図.等高線を導く間隔メートル = 間隔メートル },
        on高さ場を生成: () => 積む({ 種類: '等高線から高さ場を生成する', 値: { チャンク座標: チャンク座標() } }),
        on高さ場から導く: () => 積む({ 種類: '高さ場から等高線を導く', 値: { チャンク座標: チャンク座標(), 間隔メートル: 見下ろし図.等高線を導く間隔メートル } }),
    })

    部品.インスペクター.部品.大升.配線する({
        on一辺の升目数確定: (升目数) => {
            見下ろし図.大升の一辺の升目数 = 升目数
            部品.見下ろし図.再描画する()
        },
        on選択高さ確定: (高さメートル) => { 選択中の大升を1升だけ塗る({ 高さメートル }) },
        on選択層確定: (層) => { 選択中の大升を1升だけ塗る({ 層 }) },
        on選択を消す: () => { 選択中の大升を1升だけ塗る({ 高さメートル: null, 層: null }) },
        on高さ確定: (高さメートル) => { 見下ろし図.大升に置く高さメートル = 高さメートル },
        on高さを置くか変更: (置くか) => { 見下ろし図.大升に高さを置くか = 置くか },
        on層変更: (層) => { 見下ろし図.大升に置く層 = 層 },
        on層を置くか変更: (置くか) => { 見下ろし図.大升に層を置くか = 置くか },
        on塗りを消すか変更: (消すか) => { 見下ろし図.大升の塗りを消すか = 消すか },
        on地形を生成: () => 積む({ 種類: '大升から地形を生成する', 値: { チャンク座標: チャンク座標() } }),
        on高さ場から導く: () => 積む({ 種類: '高さ場から大升を導く', 値: { チャンク座標: チャンク座標(), 大升の一辺の升目数: 見下ろし図.大升の一辺の升目数 } }),
    })
}
