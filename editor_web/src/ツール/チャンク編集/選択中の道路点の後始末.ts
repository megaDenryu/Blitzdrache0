import type { 道路点の選択状態 } from './道路点編集の相手.ts'

// 取り消しや削除で制御点が減ると、選ばれたままの添字が居なくなった点を指し続ける。
// そのまま削除ボタンを押すと添字が範囲外になって例外になるため、道路を同期するたびに
// 現在の制御点の数と突き合わせて、行き場を失った選択を外す。
export function 居なくなった道路点の選択を外す(状態: 道路点の選択状態, 制御点の数: number): void {
    const 添字 = 状態.選択中の道路点の添字
    if (添字 !== null && 添字 >= 制御点の数) {
        状態.選択中の道路点の添字 = null
    }
}
