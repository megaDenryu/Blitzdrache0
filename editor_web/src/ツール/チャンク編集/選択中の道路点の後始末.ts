import type { 道路の一覧 } from './編集モデル/index.ts'
import type { 道路点の在り処 } from './編集モデル/index.ts'
import type { 道路点の選択状態 } from './道路点編集の相手.ts'

// 取り消しや削除で道路や制御点が減ると、選ばれたままの在り処が居なくなった点を指し続ける。
// そのまま削除ボタンを押すと添字が範囲外になって例外になるため、道路を同期するたびに
// 現在の道路一覧と突き合わせて、行き場を失った選択とアクティブな道を外す。
export function 居なくなった道路と道路点の選択を外す(状態: 道路点の選択状態, 道路一覧: 道路の一覧): void {
    状態.選択中の道路点 = 実在する在り処だけを残す(状態.選択中の道路点, 道路一覧)
    状態.つかんでいる道路点 = 実在する在り処だけを残す(状態.つかんでいる道路点, 道路一覧)
    const アクティブ = 状態.アクティブな道路の添字
    if (アクティブ !== null && !道路一覧.道路が在るか(アクティブ)) {
        状態.アクティブな道路の添字 = null
    }
}

function 実在する在り処だけを残す(在り処: 道路点の在り処 | null, 道路一覧: 道路の一覧): 道路点の在り処 | null {
    if (在り処 === null) return null
    if (!道路一覧.道路が在るか(在り処.道路添字)) return null
    const 制御点の数 = 道路一覧.道路を取り出す(在り処.道路添字).制御点列.length
    return 在り処.制御点添字 < 制御点の数 ? 在り処 : null
}
