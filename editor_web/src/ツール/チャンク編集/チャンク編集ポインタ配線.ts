import type { ポインタ事象情報, 三次元部品 } from 'SengenThree'
import { 編集対象の道路一覧 } from './編集モデル/index.ts'
import type { ワールド編集状態 } from './編集モデル/index.ts'
import type { チャンク編集画面部品 } from './画面/index.ts'
import { モード一覧 } from './画面/パネル/モード切替/モード定義.ts'
import type { チャンク編集状態 } from './チャンク編集状態.ts'
import type { チャンク編集操作サービス } from './チャンク編集操作サービス.ts'
import type { チャンク編集同期サービス } from './チャンク編集同期サービス.ts'
import { チャンク編集筆致ハンドラ } from './チャンク編集筆致ハンドラ.ts'
import { チャンク編集ポインタ振り分け } from './チャンク編集ポインタ振り分け.ts'
import { 建物のクリック選択 } from './建物のクリック選択.ts'
import { 道路点クリックハンドラ } from './道路点クリックハンドラ.ts'
import { 道路点ドラッグハンドラ } from './道路点ドラッグハンドラ.ts'
import { キーボード入力を配線する } from './画面/三次元/カメラ/キーボード配線.ts'
import { ホイールと右クリックを配線する, 視点のポインタ操作係 } from '../../三次元の視点操作/index.ts'

// 三次元ビューのポインタ操作およびレイキャスト入力を配線する。
// キーボード入力(取り消し・WASDQE移動・Altのモード循環)は画面/三次元/カメラ/キーボード配線.ts が持つ
// (大域編集ツールと共有する工程のため、ポインタ配線とは別の配線として分離してある)。
export function ポインタとキー入力を配線する(
    部品: チャンク編集画面部品,
    状態: チャンク編集状態,
    操作: チャンク編集操作サービス,
    同期: チャンク編集同期サービス,
    モデル: ワールド編集状態,
): () => void {
    const ビュー = 部品.三次元ビュー
    const 視点 = new 視点のポインタ操作係(ビュー)
    const 道路一覧 = new 編集対象の道路一覧(モデル, { 種類: 'チャンク', チャンク座標: { ...状態.対象チャンク座標 } })
    const 筆致 = new チャンク編集筆致ハンドラ(モデル, 状態, 部品, 同期)
    const 道路点クリック = new 道路点クリックハンドラ(道路一覧, 状態, ビュー, 操作, 同期)
    const 道路点ドラッグ = new 道路点ドラッグハンドラ(道路一覧, 状態, ビュー, 操作, 同期)
    const 建物選択 = new 建物のクリック選択(モデル, 状態, 部品, 同期)
    const 振り分け = new チャンク編集ポインタ振り分け(状態, ビュー.地形, 道路点クリック, 道路点ドラッグ, 建物選択)

    // 帯は道編集モードのときだけ当たり判定へ入れる。常時入れると、造成や地表ペイントで
    // 道路の上をなぞったときに地形より手前の帯が拾われて筆が止まる。
    // 道作成モードでは、既存の点をクリックして分岐を始められるようマーカーだけを入れる。
    function レイキャストの対象部品一覧を決める(): readonly 三次元部品[] {
        if (状態.モード === '道編集') return [ビュー.地形, ビュー.道路点マーカー, ビュー.道路帯, ビュー.建物]
        if (状態.モード === '道作成') return [ビュー.地形, ビュー.道路点マーカー, ビュー.建物]
        return [ビュー.地形, ビュー.建物]
    }

    // 割り当ての正本は`三次元の視点操作`が1つ持つ。右・中は全モードで常に視点、左はそのモードの主作業。
    const 移動時 = ({ 当たり一覧, 最前面当たり, 原初事象 }: ポインタ事象情報): void => {
        if (視点.視点の操作として動かしたか(原初事象)) return
        if (振り分け.動かされた(当たり一覧)) return

        if (最前面当たり !== null && 最前面当たり.部品 === ビュー.地形) {
            筆致.移動時(最前面当たり.交差点, 視点.左ボタン押下中, 原初事象.shiftKey)
        } else {
            ビュー.ブラシリング.可視性を設定する(false)
        }
    }

    ビュー.レイキャスト.配線する({
        移動時,
        押し時: ({ 当たり一覧, 原初事象 }) => {
            視点.押された(原初事象)
            if (振り分け.押された(原初事象.button, 当たり一覧)) return
            筆致.押し時(原初事象.button)
        },
        離し時: ({ 原初事象 }) => {
            視点.離された(原初事象)
            振り分け.離された(原初事象.button)
            筆致.離し時(原初事象.button)
        },
        クリック時: (事象) => 振り分け.クリックされた(事象),
    })

    ビュー.レイキャスト.キャンバスの購読を開始する({
        キャンバス: ビュー.キャンバス要素.dom.element,
        カメラ: ビュー.カメラ,
        対象部品一覧: レイキャストの対象部品一覧を決める,
    })

    const ホイールと右クリックの解除 = ホイールと右クリックを配線する(ビュー)

    const キーボード解除 = キーボード入力を配線する(部品, 状態, 操作, 同期, モード一覧)

    return () => {
        ビュー.レイキャスト.キャンバスの購読を解除する()
        ホイールと右クリックの解除()
        キーボード解除()
    }
}
