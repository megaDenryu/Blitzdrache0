import type { 編集対象の道路一覧, 道路点の在り処, 道路点の挿入先 } from './編集モデル/index.ts'
import { 道路点の挿入先を求める } from './編集モデル/index.ts'
import type { 当たりの記録, 道路点マーカーの当たり, 路面の当たり } from './道路点編集の相手.ts'

// レイキャストの当たりの一覧から、編集の相手になる道路点や道路を割り出す工程。
// クリックのハンドラとドラッグのハンドラが同じ割り出し方を共有するためにここへ集める。

// 道路点マーカーに当たっていれば、その点の在り処を返す。当たっていなければnullを返す。
export function 当たった道路点の在り処を求める(
    当たり一覧: readonly 当たりの記録[],
    道路点マーカー: 道路点マーカーの当たり,
): 道路点の在り処 | null {
    for (const 当たり of 当たり一覧) {
        if (当たり.部品.実体 !== 道路点マーカー.実体) continue
        const 在り処 = 道路点マーカー.当たった道路点の在り処を求める(当たり.原初交差情報.object)
        if (在り処 !== null) return 在り処
    }
    return null
}

// 路面への割り込み先とは、帯の上をクリックしたときに、どの道路の何番目へ点を割り込ませるかと
// その点の位置を組にしたもののことである。
export interface 路面への割り込み先 {
    readonly 道路添字: number
    readonly 挿入先: 道路点の挿入先
}

// 当たりの一覧から、路面そのものに当たった道路を探して割り込み先を求める工程。
// 散布除外バッファのメッシュは路面より広く張り出すため、路面に当たったものだけを見る。
// どの路面にも当たっていないか、区間が1つも無い道路ならnullを返す。
export function 路面への割り込み先を求める(
    当たり一覧: readonly 当たりの記録[],
    道路帯: 路面の当たり,
    道路一覧: 編集対象の道路一覧,
): 路面への割り込み先 | null {
    for (const 当たり of 当たり一覧) {
        if (当たり.部品.実体 !== 道路帯.実体) continue
        const 道路添字 = 道路帯.当たった路面の道路添字を求める(当たり.原初交差情報.object)
        if (道路添字 === null) continue
        const 交差点 = 当たり.交差点
        const 制御点列 = 道路一覧.道路を取り出す(道路添字).制御点列
        const 挿入先 = 道路点の挿入先を求める(制御点列, { x: 交差点.x, y: 交差点.y, z: 交差点.z })
        return 挿入先 === null ? null : { 道路添字, 挿入先 }
    }
    return null
}
