import type { プロジェクト保管庫接続, 読込結果 } from '../../境界/通信/index.ts'
import { 建物外形カタログ接続か } from '../../境界/通信/index.ts'
import type { 建物外形カタログ } from '../../生成/編集資源契約.ts'
import type { チャンク編集ツール } from './チャンク編集ツール.ts'

// 建物外形カタログを読み、下パネルの置ける建物の棚・三次元ビュー・操作サービスの3つへ同じ定義一覧を
// 注入する。タブを開いた時点で1回だけ反映する(カタログは編集サーバーの起動時に固定されるため)。
// 読めなかったときは無言で戻らず、失敗の理由を棚へ出す。定義が0件のままでは建物を1件も置けないため、
// 利用者が原因を知れないと道具が壊れたようにしか見えない。
export async function 建物外形カタログを注入する(ツール: チャンク編集ツール): Promise<void> {
    const 保管庫: プロジェクト保管庫接続 = ツール.保管庫
    const 置ける建物の棚 = ツール.画面.部品.棚.部品.置ける建物
    if (!建物外形カタログ接続か(保管庫)) {
        置ける建物の棚.カタログ取得失敗を表示する('この接続は建物外形カタログを提供しません')
        return
    }
    const 結果 = await 保管庫.建物外形カタログを読む()
    if (結果.種別 !== '成功') {
        置ける建物の棚.カタログ取得失敗を表示する(失敗の説明を組み立てる(結果))
        return
    }
    const 定義一覧 = 結果.値.建物定義一覧
    ツール.操作サービス.建物定義一覧を更新する(定義一覧)
    置ける建物の棚.建物定義一覧を更新する(定義一覧)
    ツール.画面.部品.三次元ビュー.建物.建物定義一覧を更新する(定義一覧)
    ツール.同期サービス.建物を同期する()
}

function 失敗の説明を組み立てる(結果: 読込結果<建物外形カタログ>): string {
    return 結果.種別 === '失敗' ? `${結果.エラー.種別} ${結果.エラー.説明}` : 'カタログがありません'
}
