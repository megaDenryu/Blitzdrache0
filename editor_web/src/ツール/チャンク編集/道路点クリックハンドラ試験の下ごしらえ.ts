// 道路点クリックハンドラの試験が使う、道が1本だけ在るチャンクとハンドラ一式の組み立て。
// 当たり判定は決め打ちの偽物へ差し替え、道の増え方とアクティブな道の移り方だけを見る。

export const チャンク座標 = { x: 0, z: 0 }

// マーカーの代わりに、渡した在り処を必ず返す当たり判定を置く。実際の描画は絵の目視で確かめる。
function 決め打ちの道路点マーカーを作る(在り処: 道路点の在り処 | null) {
    return { 実体: 当たる物体, 当たった道路点の在り処を求める: (): 道路点の在り処 | null => 在り処 }
}

function 当たらない路面を作る() {
    return { 実体: new Object3D(), 当たった路面の道路添字を求める: (): number | null => null }
}

// 当たり一覧が指す先。マーカーへ当たったことにするため、マーカーの実体と同じ物体を使う。
const 当たる物体 = new Object3D()

export function 初期状態を作る(): ワールド編集状態 {
    const 大域構造: 大域世界構造 = {
        区画割り: { 一辺のメートル: 512, 軸あたりチャンク数: 2, チャンクあたり格子解像度: 33 },
        広域道路一覧: [],
    }
    const 状態 = new ワールド編集状態(大域構造)
    const 構造: チャンク構造 = {
        道路一覧: [{
            制御点列: [{ x: -10, y: 1, z: 0 }, { x: 10, y: 2, z: 0 }],
            全幅メートル: 7,
            散布除外バッファメートル: 13,
            細分割数: 40,
        }],
        建物一覧: [],
        散布: { 最小間隔メートル: 5, 乱数の種: 1n },
    }
    状態.チャンクを登録する(チャンク座標, 構造)
    状態.選択中チャンク座標 = チャンク座標
    return 状態
}

export function ハンドラを組む(モデル: ワールド編集状態, 当たる在り処: 道路点の在り処 | null) {
    const 道路一覧 = new 編集対象の道路一覧(モデル, { 種類: 'チャンク', チャンク座標 })
    const 選択状態: 道路点の選択状態 = { アクティブな道路の添字: 0, 選択中の道路点: null, つかんでいる道路点: null }
    const ビュー = {
        道路点マーカー: 決め打ちの道路点マーカーを作る(当たる在り処),
        道路帯: 当たらない路面を作る(),
        地形: { 実体: new Object3D() },
    }
    const 操作 = { コマンドを実行する: (コマンド: 編集コマンド) => { 編集コマンドを適用する(モデル, コマンド) } }
    const 同期 = { 道路を同期する: () => {}, UIを同期する: () => {} }
    return { 選択状態, ハンドラ: new 道路点クリックハンドラ(道路一覧, 選択状態, ビュー, 操作, 同期) }
}

