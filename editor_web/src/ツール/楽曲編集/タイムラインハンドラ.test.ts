import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import { 楽曲編集コマンドを適用する } from './操作コマンド/index.ts'
import { 楽曲履歴適用サービス } from './操作コマンド/楽曲履歴適用サービス.ts'
import { タイムラインハンドラ } from './タイムラインハンドラ.ts'
import { 楽曲編集UI状態 } from './楽曲編集UI状態.ts'
import { 楽曲編集状態 } from './編集モデル/index.ts'

// on節移動・onカード操作が積んだ後、選択中のカードと選択中パターンの名乗りが
// 操作の後の位置へ追従することを固定する(issue #88)。何もしない`表示を再構築する`を渡す。
describe('タイムラインハンドラの選択追従テスト', () => {
    function 状態一式を組み立てる(): { 状態: 楽曲編集状態; UI状態: 楽曲編集UI状態; ハンドラ: タイムラインハンドラ } {
        const 状態 = new 楽曲編集状態()
        for (const 名乗り of ['A', 'B']) {
            楽曲編集コマンドを適用する(状態, {
                種類: 'パターンを追加する',
                値: { 名乗り, 表示名: 名乗り, 進行の参照: { 種類: '既定の進行', 識別子: '王道進行' } },
            })
        }
        状態.楽曲.曲構成 = [
            { パターンの名乗り: 'A', 繰り返し回数: 2 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
        ]
        const UI状態 = new 楽曲編集UI状態()
        const 操作 = new 楽曲履歴適用サービス(状態)
        const ハンドラ = new タイムラインハンドラ(状態, UI状態, 操作, () => {})
        return { 状態, UI状態, ハンドラ }
    }

    it('Bを選んで前へ移動すると、曲構成が[B, A×2]になり選択がBへ追従すること', () => {
        const { 状態, UI状態, ハンドラ } = 状態一式を組み立てる()
        UI状態.選択中のカード = { 節の位置: 1, 繰り返しの何回目: 0 }

        ハンドラ.on節移動({ 節の位置: 1, 繰り返しの何回目: 0 }, '前へ移動')

        assert.deepEqual(状態.楽曲.曲構成, [
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
            { パターンの名乗り: 'A', 繰り返し回数: 2 },
        ])
        assert.deepEqual(UI状態.選択中のカード, { 節の位置: 0, 繰り返しの何回目: 0 })
        assert.equal(状態.選択中パターンの名乗り, 'B')
    })

    it('Aの2枚目を選んで枠の後へ移動を押すと、繰り返しの何回目を保ったままAへ追従すること', () => {
        const { 状態, UI状態, ハンドラ } = 状態一式を組み立てる()
        UI状態.選択中のカード = { 節の位置: 0, 繰り返しの何回目: 1 }

        ハンドラ.on節移動({ 節の位置: 0, 繰り返しの何回目: 0 }, '後へ移動')

        assert.deepEqual(UI状態.選択中のカード, { 節の位置: 1, 繰り返しの何回目: 1 })
        assert.equal(状態.選択中パターンの名乗り, 'A')
    })

    it('削除すると選択中のカードが外れ、選択中パターンの名乗りは変わらないこと', () => {
        const { 状態, UI状態, ハンドラ } = 状態一式を組み立てる()
        状態.選択中パターンの名乗り = 'A'
        UI状態.選択中のカード = { 節の位置: 0, 繰り返しの何回目: 1 }

        ハンドラ.onカード操作({ 節の位置: 0, 繰り返しの何回目: 1 }, '削除')

        assert.equal(UI状態.選択中のカード, null)
        assert.equal(状態.選択中パターンの名乗り, 'A')
    })

    it('Bの前へ挿入を押すと、後ろへずれた元のBへ選択が追従すること', () => {
        const { 状態, UI状態, ハンドラ } = 状態一式を組み立てる()
        UI状態.選択中のカード = { 節の位置: 1, 繰り返しの何回目: 0 }

        ハンドラ.onカード操作({ 節の位置: 1, 繰り返しの何回目: 0 }, '前へ挿入')

        assert.deepEqual(状態.楽曲.曲構成, [
            { パターンの名乗り: 'A', 繰り返し回数: 2 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
        ])
        assert.deepEqual(UI状態.選択中のカード, { 節の位置: 2, 繰り返しの何回目: 0 })
        assert.equal(状態.選択中パターンの名乗り, 'B')
    })
})
