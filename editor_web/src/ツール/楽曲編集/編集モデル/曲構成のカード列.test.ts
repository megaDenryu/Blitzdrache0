import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import { type パターン, type 曲の節 } from '../../../生成/編集資源契約.ts'
import { カード位置は同じか, 曲構成をカードの列へ展開する } from './曲構成のカード列.ts'

function パターンを作る(名乗り: string, 小節数: number): パターン {
    return {
        名乗り,
        表示名: 名乗り,
        小節数,
        進行の参照: { 種類: '既定の進行', 識別子: '街とやすらぎ' },
        格子: [],
    }
}

describe('曲構成をカードの列へ展開するテスト', () => {
    it('曲構成が空なら空の列を返すこと', () => {
        const 空曲構成: 曲の節[] = []
        assert.deepEqual(曲構成をカードの列へ展開する(空曲構成, []), [])
    })

    it('小節数2のA×2, 小節数2のB×1の曲構成が6枚のカードへ展開され、小節番号と始まりの通しステップが一致すること', () => {
        const パターン一覧 = [パターンを作る('A', 2), パターンを作る('B', 2)]
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'A', 繰り返し回数: 2 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
        ]
        const カード列 = 曲構成をカードの列へ展開する(曲構成, パターン一覧)

        assert.equal(カード列.length, 6)

        assert.equal(カード列[0].パターンの名乗り, 'A')
        assert.ok(カード位置は同じか(カード列[0].位置, { 節の位置: 0, 繰り返しの何回目: 0, 小節の番号: 0 }))
        assert.equal(カード列[0].始まりの通しステップ.数値(), 0)
        assert.equal(カード列[0].曲全体での小節番号, 1)

        assert.ok(カード位置は同じか(カード列[1].位置, { 節の位置: 0, 繰り返しの何回目: 0, 小節の番号: 1 }))
        assert.equal(カード列[1].始まりの通しステップ.数値(), 16)
        assert.equal(カード列[1].曲全体での小節番号, 2)

        assert.ok(カード位置は同じか(カード列[2].位置, { 節の位置: 0, 繰り返しの何回目: 1, 小節の番号: 0 }))
        assert.equal(カード列[2].始まりの通しステップ.数値(), 32)
        assert.equal(カード列[2].曲全体での小節番号, 3)

        assert.equal(カード列[4].パターンの名乗り, 'B')
        assert.ok(カード位置は同じか(カード列[4].位置, { 節の位置: 1, 繰り返しの何回目: 0, 小節の番号: 0 }))
        assert.equal(カード列[4].始まりの通しステップ.数値(), 64)
        assert.equal(カード列[4].曲全体での小節番号, 5)
    })

    it('小節数が節ごとに違うA(2小節)×2, B(1小節)×1, C(4小節)×1の曲構成が9枚のカードへ展開されること', () => {
        const パターン一覧 = [パターンを作る('A', 2), パターンを作る('B', 1), パターンを作る('C', 4)]
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'A', 繰り返し回数: 2 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
            { パターンの名乗り: 'C', 繰り返し回数: 1 },
        ]
        const カード列 = 曲構成をカードの列へ展開する(曲構成, パターン一覧)

        assert.equal(カード列.length, 9)
        assert.deepEqual(
            カード列.map((カード) => カード.始まりの通しステップ.数値()),
            [0, 16, 32, 48, 64, 80, 96, 112, 128],
        )
        assert.deepEqual(
            カード列.map((カード) => カード.曲全体での小節番号),
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
        )
        assert.equal(カード列[4].パターンの名乗り, 'B')
        assert.ok(カード位置は同じか(カード列[4].位置, { 節の位置: 1, 繰り返しの何回目: 0, 小節の番号: 0 }))
        assert.equal(カード列[5].パターンの名乗り, 'C')
        assert.ok(カード位置は同じか(カード列[5].位置, { 節の位置: 2, 繰り返しの何回目: 0, 小節の番号: 0 }))
        assert.ok(カード位置は同じか(カード列[8].位置, { 節の位置: 2, 繰り返しの何回目: 0, 小節の番号: 3 }))
    })

    it('カード位置は同じかが節の位置・繰り返しの何回目・小節の番号の3つ全部の一致で判定すること', () => {
        const 一方 = { 節の位置: 1, 繰り返しの何回目: 2, 小節の番号: 0 }
        assert.ok(カード位置は同じか(一方, { 節の位置: 1, 繰り返しの何回目: 2, 小節の番号: 0 }))
        assert.ok(!カード位置は同じか(一方, { 節の位置: 1, 繰り返しの何回目: 3, 小節の番号: 0 }))
        assert.ok(!カード位置は同じか(一方, { 節の位置: 0, 繰り返しの何回目: 2, 小節の番号: 0 }))
        assert.ok(!カード位置は同じか(一方, { 節の位置: 1, 繰り返しの何回目: 2, 小節の番号: 1 }))
    })
})
