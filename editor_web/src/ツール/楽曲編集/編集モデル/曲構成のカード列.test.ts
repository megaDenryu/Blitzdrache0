import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import { パターンのステップ数, type 曲の節 } from '../../../生成/編集資源契約.ts'
import { 曲全体のステップ数を計算する } from './曲構成の計算.ts'
import { カード位置は同じか, 曲構成をカードの列へ展開する } from './曲構成のカード列.ts'

describe('曲構成をカードの列へ展開するテスト', () => {
    it('曲構成が空なら空の列を返すこと', () => {
        const 空曲構成: 曲の節[] = []
        assert.deepEqual(曲構成をカードの列へ展開する(空曲構成), [])
    })

    it('A×2, B×1の曲構成が3枚のカードへ展開され、小節番号と始まりの通しステップが一致すること', () => {
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'A', 繰り返し回数: 2 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
        ]
        const カード列 = 曲構成をカードの列へ展開する(曲構成)

        assert.equal(カード列.length, 3)

        assert.equal(カード列[0].パターンの名乗り, 'A')
        assert.ok(カード位置は同じか(カード列[0].位置, { 節の位置: 0, 繰り返しの何回目: 0 }))
        assert.equal(カード列[0].始まりの通しステップ.数値(), 0)
        assert.deepEqual(カード列[0].小節番号の範囲, { 始まりの小節番号: 1, 終わりの小節番号: 2 })

        assert.equal(カード列[1].パターンの名乗り, 'A')
        assert.ok(カード位置は同じか(カード列[1].位置, { 節の位置: 0, 繰り返しの何回目: 1 }))
        assert.equal(カード列[1].始まりの通しステップ.数値(), 32)
        assert.deepEqual(カード列[1].小節番号の範囲, { 始まりの小節番号: 3, 終わりの小節番号: 4 })

        assert.equal(カード列[2].パターンの名乗り, 'B')
        assert.ok(カード位置は同じか(カード列[2].位置, { 節の位置: 1, 繰り返しの何回目: 0 }))
        assert.equal(カード列[2].始まりの通しステップ.数値(), 64)
        assert.deepEqual(カード列[2].小節番号の範囲, { 始まりの小節番号: 5, 終わりの小節番号: 6 })
    })

    it('カードの列の全体のステップ数が曲全体のステップ数を計算するの結果と一致すること', () => {
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'A', 繰り返し回数: 2 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
            { パターンの名乗り: 'C', 繰り返し回数: 3 },
        ]
        const カード列 = 曲構成をカードの列へ展開する(曲構成)
        const カード列の全体ステップ数 = カード列.length * パターンのステップ数

        assert.equal(カード列の全体ステップ数, 曲全体のステップ数を計算する(曲構成))
    })

    it('カード位置は同じかが節の位置と繰り返しの何回目の両方の一致で判定すること', () => {
        const 一方 = { 節の位置: 1, 繰り返しの何回目: 2 }
        assert.ok(カード位置は同じか(一方, { 節の位置: 1, 繰り返しの何回目: 2 }))
        assert.ok(!カード位置は同じか(一方, { 節の位置: 1, 繰り返しの何回目: 3 }))
        assert.ok(!カード位置は同じか(一方, { 節の位置: 0, 繰り返しの何回目: 2 }))
    })
})
