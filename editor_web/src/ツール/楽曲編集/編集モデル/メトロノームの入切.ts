// メトロノームを鳴らすかどうかの切り替え。
// 楽曲のデータではなく演奏を助ける道具の側の状態であるため、楽曲にも保存にも入らない(設計正本の判断14)。
// 拍の予約は入切に関わらず積み、鳴らす瞬間にこの値を読む。予約の側で止めると、
// 切ってから先読みの幅のあいだ鳴り続けてしまうためである。
export class メトロノームの入切 {
    private _入っているか: boolean = false

    public get 入っているか(): boolean {
        return this._入っているか
    }

    public 切り替える(): void {
        this._入っているか = !this._入っているか
    }
}
