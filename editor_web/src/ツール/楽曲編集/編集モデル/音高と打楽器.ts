import type { トラック定義, 和音 } from '../../../生成/編集資源契約.ts'
import { あるステップの和音を取得する, 和音が許す音のピッチクラス一覧 } from './音楽理論.ts'

// 音高番号から周波数（ヘルツ）を計算する。A4(69)=440Hz基準。
export function 音高番号から周波数ヘルツを計算する(音高番号: number): number {
    return 440 * Math.pow(2, (音高番号 - 69) / 12)
}

// 指定した音高番号が、その和音の構成音（ピッチクラス）として許されるかを判定する。
export function 音高番号はその和音で許されるか(音高番号: number, 対象の和音: 和音): boolean {
    const ピッチクラス = ((音高番号 % 12) + 12) % 12
    const 許容ピッチクラス一覧 = 和音が許す音のピッチクラス一覧(対象の和音)
    return 許容ピッチクラス一覧.includes(ピッチクラス)
}

// トラックの指定行・指定ステップの音が許されるかを判定する。打楽器や和音制約なし(null)は常に許す。
export function トラックの行の音はステップで許されるか(
    トラック: トラック定義,
    行の位置: number,
    ステップ: number,
    和音一覧: readonly 和音[] | null,
): boolean {
    if (和音一覧 === null || トラック.種類 === '打楽器') {
        return true
    }
    if (トラック.音の並び.種類 === '打楽器の行一覧') {
        return true
    }
    const 音高番号 = トラック.音の並び.値[行の位置]
    if (音高番号 === undefined) {
        throw new Error(`トラック「${トラック.表示名}」の行位置 ${行の位置} が範囲外です`)
    }
    const 和音 = あるステップの和音を取得する(和音一覧, ステップ)
    return 音高番号はその和音で許されるか(音高番号, 和音)
}
