import {
    type 和音,
    type 和音の種類,
} from '../../../生成/編集資源契約.ts'

const 和音音程対応表: Record<和音の種類, readonly number[]> = {
    長三和音: [0, 4, 7],
    短三和音: [0, 3, 7],
    長七の和音: [0, 4, 7, 11],
    短七の和音: [0, 3, 7, 10],
    属七の和音: [0, 4, 7, 10],
    四度掛留の和音: [0, 5, 7],
    減三和音: [0, 3, 6],
    増三和音: [0, 4, 8],
}

const 和音表記記号対応表: Record<和音の種類, string> = {
    長三和音: '',
    短三和音: 'm',
    長七の和音: 'M7',
    短七の和音: 'm7',
    属七の和音: '7',
    四度掛留の和音: 'sus4',
    減三和音: 'dim',
    増三和音: 'aug',
}

// 和音の種類に応じた根音からの音程一覧（半音単位）。ハズレ音を構造的に作らない集合。
export function 和音の種類に応じた音程一覧(種類: 和音の種類): readonly number[] {
    return 和音音程対応表[種類]
}

// 和音の種類に応じた表記記号を返す。
export function 和音の種類の表記記号(種類: 和音の種類): string {
    return 和音表記記号対応表[種類]
}

const 音名一覧: readonly string[] = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B']

// 和音の表示名（例: C, Am, G7）を組み立てる。
export function 和音の表示名を組み立てる(対象の和音: 和音): string {
    const 根音位置 = ((対象の和音.根音 % 12) + 12) % 12
    const 音名 = 音名一覧[根音位置]
    if (音名 === undefined) {
        throw new Error(`根音位置 ${根音位置} に対応する音名が存在しません`)
    }
    return `${音名}${和音の種類の表記記号(対象の和音.種類)}`
}

// 和音が許す音のピッチクラス（0〜11）の一覧を返す。
export function 和音が許す音のピッチクラス一覧(対象の和音: 和音): readonly number[] {
    const 音程一覧 = 和音の種類に応じた音程一覧(対象の和音.種類)
    return 音程一覧.map((音程) => ((対象の和音.根音 + 音程) % 12 + 12) % 12)
}

// 指定したステップの位置で鳴っている和音を周期的に解決して返す。
export function あるステップの和音を取得する(和音一覧: readonly 和音[], ステップ: number): 和音 {
    if (和音一覧.length === 0) {
        throw new Error('和音一覧が空のためステップの和音を特定できません')
    }
    const 合計ステップ数 = 和音一覧.reduce((合計, 現在の和音) => 合計 + 現在の和音.続くステップ数, 0)
    let 残りステップ = ((ステップ % 合計ステップ数) + 合計ステップ数) % 合計ステップ数
    for (const 現在の和音 of 和音一覧) {
        if (残りステップ < 現在の和音.続くステップ数) {
            return 現在の和音
        }
        残りステップ -= 現在の和音.続くステップ数
    }
    return 和音一覧[和音一覧.length - 1]
}

// 進行の帯の区切り（格子のステップ数分を埋める和音区切りの列）。
export type 進行の帯の区切り = {
    readonly 和音: 和音
    readonly ステップ幅: number
    readonly 周回後か: boolean
}

// 格子のステップ数を埋める和音区切りの一覧を計算する。進行1周後は周回後の印を付ける。
// 格子のステップ数はパターンの小節数によって節ごとに違うため、呼び出し側が渡す。
export function 進行の帯の区切り一覧を計算する(
    和音一覧: readonly 和音[],
    格子のステップ数: number,
): readonly 進行の帯の区切り[] {
    if (和音一覧.length === 0) {
        return []
    }
    const 区切り一覧: 進行の帯の区切り[] = []
    let ステップ = 0
    let 和音添字 = 0
    while (ステップ < 格子のステップ数) {
        const 現在の和音 = 和音一覧[和音添字 % 和音一覧.length]
        const ステップ幅 = Math.min(現在の和音.続くステップ数, 格子のステップ数 - ステップ)
        区切り一覧.push({
            和音: 現在の和音,
            ステップ幅,
            周回後か: 和音添字 >= 和音一覧.length,
        })
        ステップ += ステップ幅
        和音添字++
    }
    return 区切り一覧
}
