import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import { type 和音 } from '../../../生成/編集資源契約.ts'
import { 小節数からステップ数を求める } from './パターンの長さ.ts'
import { あるステップの和音を取得する, 進行の帯の区切り一覧を計算する } from './音楽理論.ts'

// 和音1つが10ステップ続き、3つで30ステップを1周する進行。1周が小節の区切りと揃わないため、
// 1小節のパターンでは2つ目の和音の途中で打ち切られ、3小節のパターンでは1周した後に先頭へ戻り、2つ目の和音の途中で打ち切られる。
const 小節と揃わない進行: readonly 和音[] = [
    { 根音: 0, 種類: '長三和音', 続くステップ数: 10 },
    { 根音: 9, 種類: '短三和音', 続くステップ数: 10 },
    { 根音: 5, 種類: '長三和音', 続くステップ数: 10 },
]

// パターンの各ステップで鳴る和音の根音を、先頭から順に並べる。
function 各ステップの根音を並べる(ステップ数: number): readonly number[] {
    return Array.from({ length: ステップ数 }, (_, ステップ) => あるステップの和音を取得する(小節と揃わない進行, ステップ).根音)
}

// 進行の帯の区切りを1ステップずつに展開し、帯が示す根音を先頭から順に並べる。
function 進行の帯が示す根音を並べる(ステップ数: number): readonly number[] {
    return 進行の帯の区切り一覧を計算する(小節と揃わない進行, ステップ数).flatMap((区切り) =>
        Array.from({ length: 区切り.ステップ幅 }, () => 区切り.和音.根音),
    )
}

describe('ステップから和音への写像', () => {
    it('ステップから和音への写像が周回および打ち切りを含めて正しく動作すること', () => {
        const 短い進行: 和音[] = [
            { 根音: 0, 種類: '長三和音', 続くステップ数: 4 },
            { 根音: 9, 種類: '短三和音', 続くステップ数: 4 },
            { 根音: 5, 種類: '長三和音', 続くステップ数: 4 },
            { 根音: 7, 種類: '長三和音', 続くステップ数: 4 },
        ]
        assert.equal(あるステップの和音を取得する(短い進行, 0).根音, 0)
        assert.equal(あるステップの和音を取得する(短い進行, 3).根音, 0)
        assert.equal(あるステップの和音を取得する(短い進行, 4).根音, 9)
        assert.equal(あるステップの和音を取得する(短い進行, 15).根音, 7)
        assert.equal(あるステップの和音を取得する(短い進行, 16).根音, 0)
        assert.equal(あるステップの和音を取得する(短い進行, 20).根音, 9)
    })

    it('1小節のパターンでは、進行が1周に届かず2つ目の和音の途中で打ち切られること', () => {
        const ステップ数 = 小節数からステップ数を求める(1)
        const 期待 = [...Array<number>(10).fill(0), ...Array<number>(6).fill(9)]
        assert.deepEqual(各ステップの根音を並べる(ステップ数), 期待)
        assert.deepEqual(進行の帯が示す根音を並べる(ステップ数), 期待)
        const 区切り一覧 = 進行の帯の区切り一覧を計算する(小節と揃わない進行, ステップ数)
        assert.deepEqual(区切り一覧.map((区切り) => 区切り.ステップ幅), [10, 6])
        assert.deepEqual(区切り一覧.map((区切り) => 区切り.周回後か), [false, false])
    })

    it('3小節のパターンでは、進行が1周した後に先頭へ戻り、2つ目の和音の途中で打ち切られること', () => {
        const ステップ数 = 小節数からステップ数を求める(3)
        const 期待 = [
            ...[0, 9, 5, 0].flatMap((根音) => Array<number>(10).fill(根音)),
            ...Array<number>(8).fill(9),
        ]
        assert.deepEqual(各ステップの根音を並べる(ステップ数), 期待)
        assert.deepEqual(進行の帯が示す根音を並べる(ステップ数), 期待)
        const 区切り一覧 = 進行の帯の区切り一覧を計算する(小節と揃わない進行, ステップ数)
        assert.deepEqual(区切り一覧.map((区切り) => 区切り.ステップ幅), [10, 10, 10, 10, 8])
        assert.deepEqual(区切り一覧.map((区切り) => 区切り.周回後か), [false, false, false, true, true])
    })
})
