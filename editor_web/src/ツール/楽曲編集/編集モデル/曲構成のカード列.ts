import {
    パターンのステップ数 as 既定パターンのステップ数,
    type 曲の節,
} from '../../../生成/編集資源契約.ts'
import { 小節あたりのステップ数, ステップ } from './演奏の時刻/index.ts'

// 曲構成の節のうち、繰り返しの何回目かを指す位置。節の位置と繰り返しの何回目は
// カード1枚を指す識別子として常に組で扱うため、1つの型へ束ねる。
export type カード位置 = {
    readonly 節の位置: number
    readonly 繰り返しの何回目: number
}

export function カード位置は同じか(一方: カード位置, 他方: カード位置): boolean {
    return 一方.節の位置 === 他方.節の位置 && 一方.繰り返しの何回目 === 他方.繰り返しの何回目
}

// カード1枚が占める、曲の何小節目から何小節目かを表す1始まりの範囲。
export type 小節番号の範囲 = {
    readonly 始まりの小節番号: number
    readonly 終わりの小節番号: number
}

// 曲構成の節の繰り返し1回分(パターン1面、2小節)を表す、タイムラインの1枚の部品。
export type 曲構成のカード = {
    readonly 位置: カード位置
    readonly パターンの名乗り: string
    readonly 始まりの通しステップ: ステップ
    readonly 小節番号の範囲: 小節番号の範囲
}

function 一枚のカードを組み立てる(
    位置: カード位置,
    パターンの名乗り: string,
    始まりの通しステップ: ステップ,
    パターンのステップ数: number,
): 曲構成のカード {
    const 小節あたりの枚数 = パターンのステップ数 / 小節あたりのステップ数
    const 始まりの小節番号 = 始まりの通しステップ.数値() / 小節あたりのステップ数 + 1
    return {
        位置,
        パターンの名乗り,
        始まりの通しステップ,
        小節番号の範囲: {
            始まりの小節番号,
            終わりの小節番号: 始まりの小節番号 + 小節あたりの枚数 - 1,
        },
    }
}

// 曲構成をカードの列へ展開する。曲構成が空なら空の列を返す。
export function 曲構成をカードの列へ展開する(
    曲構成: readonly 曲の節[],
    パターンのステップ数: number = 既定パターンのステップ数,
): readonly 曲構成のカード[] {
    const カード列: 曲構成のカード[] = []
    let 通しステップ = ステップ.ゼロ()
    曲構成.forEach((節, 節の位置) => {
        for (let 繰り返しの何回目 = 0; 繰り返しの何回目 < 節.繰り返し回数; 繰り返しの何回目++) {
            カード列.push(
                一枚のカードを組み立てる(
                    { 節の位置, 繰り返しの何回目 },
                    節.パターンの名乗り,
                    通しステップ,
                    パターンのステップ数,
                ),
            )
            通しステップ = 通しステップ.足す(ステップ.生成する(パターンのステップ数))
        }
    })
    return カード列
}
