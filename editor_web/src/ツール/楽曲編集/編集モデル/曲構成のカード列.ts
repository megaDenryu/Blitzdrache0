import { type 曲の節, type パターン } from '../../../生成/編集資源契約.ts'
import { 小節あたりのステップ数, ステップ } from './演奏の時刻/index.ts'
import { 名乗りでパターンを探す } from './パターンを探す.ts'

// 曲構成の節のうち、繰り返しの何回目かと、そのパターンの中の何小節目かを指す位置。
// カード1枚を指す識別子として常に組で扱うため、1つの型へ束ねる。
export type カード位置 = {
    readonly 節の位置: number
    readonly 繰り返しの何回目: number
    readonly 小節の番号: number
}

export function カード位置は同じか(一方: カード位置, 他方: カード位置): boolean {
    return (
        一方.節の位置 === 他方.節の位置 &&
        一方.繰り返しの何回目 === 他方.繰り返しの何回目 &&
        一方.小節の番号 === 他方.小節の番号
    )
}

// 曲構成の節が展開する1小節ぶんを表す、タイムラインの1枚の部品。
export type 曲構成のカード = {
    readonly 位置: カード位置
    readonly パターンの名乗り: string
    readonly 始まりの通しステップ: ステップ
    readonly 曲全体での小節番号: number
}

// 1つの節の繰り返し1回分の展開の当てどころ。呼び出しのたびに揃って渡される値のため1つに束ねる。
type 節の1回分の展開の当てどころ = {
    readonly 節の位置: number
    readonly 節: 曲の節
    readonly パターン: パターン
    readonly 繰り返しの何回目: number
    readonly 通しステップ起点: ステップ
    readonly 曲全体での小節番号起点: number
}

// 1つの節の繰り返し1回分を、パターンの小節数ぶんのカードへ展開する。
function 節の1回分をカードへ展開する(当てどころ: 節の1回分の展開の当てどころ): readonly 曲構成のカード[] {
    const カード列: 曲構成のカード[] = []
    for (let 小節の番号 = 0; 小節の番号 < 当てどころ.パターン.小節数; 小節の番号++) {
        カード列.push({
            位置: { 節の位置: 当てどころ.節の位置, 繰り返しの何回目: 当てどころ.繰り返しの何回目, 小節の番号 },
            パターンの名乗り: 当てどころ.節.パターンの名乗り,
            始まりの通しステップ: 当てどころ.通しステップ起点.足す(ステップ.生成する(小節の番号 * 小節あたりのステップ数)),
            曲全体での小節番号: 当てどころ.曲全体での小節番号起点 + 小節の番号,
        })
    }
    return カード列
}

// 曲構成をカードの列へ展開する。節ごとにパターンの小節数が違うため、パターン一覧から都度引き当てる。
// 曲構成が空なら空の列を返す。
export function 曲構成をカードの列へ展開する(
    曲構成: readonly 曲の節[],
    パターン一覧: readonly パターン[],
): readonly 曲構成のカード[] {
    const カード列: 曲構成のカード[] = []
    let 通しステップ = ステップ.ゼロ()
    let 曲全体での小節番号 = 1
    曲構成.forEach((節, 節の位置) => {
        const パターン = 名乗りでパターンを探す(パターン一覧, 節.パターンの名乗り)
        for (let 繰り返しの何回目 = 0; 繰り返しの何回目 < 節.繰り返し回数; 繰り返しの何回目++) {
            カード列.push(
                ...節の1回分をカードへ展開する({
                    節の位置,
                    節,
                    パターン,
                    繰り返しの何回目,
                    通しステップ起点: 通しステップ,
                    曲全体での小節番号起点: 曲全体での小節番号,
                }),
            )
            通しステップ = 通しステップ.足す(ステップ.生成する(パターン.小節数 * 小節あたりのステップ数))
            曲全体での小節番号 += パターン.小節数
        }
    })
    return カード列
}
