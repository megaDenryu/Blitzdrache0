import type { 打ち込みの対象 } from '../../../生成/編集資源契約.ts'

// 打ち込みの対象が指す格子の1行を所有し、ステップの位置が行の内側であることを確かめてから読み書きする。
// 注意: 生の数値配列を範囲外の位置で読むと undefined が返り、既定値で埋めると打点なしとして黙って通る。
// 行の所有と位置の判定をこの型へ閉じ、範囲の外は必ず失敗させる。
export class 打ち込み先の行 {
    private readonly _セルの数値の並び: number[]
    private readonly _対象: 打ち込みの対象

    public constructor(セルの数値の並び: number[], 対象: 打ち込みの対象) {
        this._セルの数値の並び = セルの数値の並び
        this._対象 = 対象
    }

    public ステップのセルの数値を読む(ステップ: number): number {
        this._ステップが行の内側であることを確かめる(ステップ)
        return this._セルの数値の並び[ステップ]
    }

    // 始まりから終わりまでの値をまとめて読む。範囲の外を含むときは1つも読まずに失敗する。
    public 範囲のセルの数値を読む(始まりのステップ: number, 終わりのステップ: number): number[] {
        const 数値一覧: number[] = []
        for (let ステップ = 始まりのステップ; ステップ <= 終わりのステップ; ステップ++) {
            数値一覧.push(this.ステップのセルの数値を読む(ステップ))
        }
        return 数値一覧
    }

    public ステップのセルの数値を書き換える(ステップ: number, 新しい数値: number): void {
        this._ステップが行の内側であることを確かめる(ステップ)
        this._セルの数値の並び[ステップ] = 新しい数値
    }

    private _ステップが行の内側であることを確かめる(ステップ: number): void {
        if (Number.isInteger(ステップ) && ステップ >= 0 && ステップ < this._セルの数値の並び.length) {
            return
        }
        throw new Error(
            `ステップが格子の行の外です: パターン=${this._対象.パターンの名乗り}`
            + ` トラックの位置=${this._対象.トラックの位置} 行の位置=${this._対象.行の位置}`
            + ` ステップ=${ステップ} 行のステップ数=${this._セルの数値の並び.length}`,
        )
    }
}
