import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { 楽曲 } from '../../../生成/編集資源契約.ts'
import { 初期楽曲を生成する } from './初期楽曲生成.ts'
import { 楽曲編集状態 } from './楽曲編集状態.ts'

function パターンを持たない楽曲を組み立てる(): 楽曲 {
    return { ...初期楽曲を生成する(), パターン一覧: [] }
}

describe('選択中パターンの未選択の扱い', () => {
    it('パターンを持つ楽曲では先頭のパターンが選ばれる', () => {
        const 状態 = new 楽曲編集状態()
        assert.equal(状態.選択中パターンの名乗り, 'pattern-1')
        assert.equal(状態.選択中パターンを取得する().名乗り, 'pattern-1')
    })

    it('パターンを持たない楽曲では未選択になり、名乗りが空文字にならない', () => {
        const 状態 = new 楽曲編集状態(パターンを持たない楽曲を組み立てる())
        assert.equal(状態.選択中パターンの名乗り, null)
    })

    it('未選択のまま選択中パターンを取得すると失敗する', () => {
        const 状態 = new 楽曲編集状態(パターンを持たない楽曲を組み立てる())
        assert.throws(() => 状態.選択中パターンを取得する(), /パターンが1つも無いため/)
    })

    it('パターンを持たない楽曲で上書きすると未選択へ戻る', () => {
        const 状態 = new 楽曲編集状態()
        状態.状態を上書きする(パターンを持たない楽曲を組み立てる())
        assert.equal(状態.選択中パターンの名乗り, null)
    })

    it('選択中のパターンが消えたら先頭のパターンへ選び直す', () => {
        const 楽曲 = 初期楽曲を生成する()
        const 状態 = new 楽曲編集状態(楽曲)
        状態.選択中パターンの名乗り = '存在しないパターン'
        状態.選択中パターンが失われていたら選び直す()
        assert.equal(状態.選択中パターンの名乗り, 'pattern-1')
    })
})
