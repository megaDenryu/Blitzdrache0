import { 小節あたりのステップ数 } from '../../../../生成/編集資源契約.ts'
import type { ステップ } from './ステップ.ts'

// 1拍を4つのステップ(16分音符)へ割る楽曲エディターの取り決め。
// テンポがステップを秒へ換算するときと、メトロノームが拍の頭を数えるときの両方が同じ取り決めを使うため、
// 数をこの1箇所へ集めて2つが食い違わないようにする。
export const 拍あたりのステップ数 = 4

// 小節あたりのステップ数の正本は契約(型契約)であり、ここは演奏の時刻の計算から使うための再公開である。
export { 小節あたりのステップ数 }

// 拍の頭のうち、メトロノームが打ち分ける2種。小節の頭を他の拍と違う音にすると、数えなくても小節の切れ目が耳で分かる。
export type 拍の頭の種類 = '小節の頭' | '小節の中の拍'

// 通しステップを拍と小節の枠に照らした位置づけ。
export type 拍の位置づけ = 拍の頭の種類 | '拍の頭でない'

// 演奏を始めてから数えた通しステップが、拍と小節の枠のどこに当たるかを答える。
// ステップのメソッドにしないのは、ステップが位置だけでなく音の長さも表す型であり、長さには枠の中の位置が無いためである。
export function 通しステップの拍の位置づけを求める(通しステップ: ステップ): 拍の位置づけ {
    if (通しステップ.数値() % 拍あたりのステップ数 !== 0) return '拍の頭でない'
    return 通しステップ.数値() % 小節あたりのステップ数 === 0 ? '小節の頭' : '小節の中の拍'
}
