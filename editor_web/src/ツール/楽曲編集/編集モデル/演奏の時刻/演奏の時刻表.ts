import { ステップ } from './ステップ.ts'
import type { 拍毎分 } from './拍毎分.ts'
import { 秒数 } from './秒数.ts'

export interface 演奏の時刻表構築引数 {
    readonly 基準の時刻: 秒数
    readonly 基準の通しステップ: ステップ
    readonly 拍毎分: 拍毎分
}

// 演奏を始めてから数えた通しのステップと、音声の時計の時刻とを行き来する表。
// 基準となる時刻とステップの対を持ち、そこからの差をステップ1つ分の秒数で換算する。
// 拍毎分が変わったら、その時点の時刻とステップで基準を置き直す。既に予約した音の時刻は動かさないためである。
export class 演奏の時刻表 {
    private _基準の時刻: 秒数
    private _基準の通しステップ: ステップ
    private _拍毎分: 拍毎分

    public constructor(引数: 演奏の時刻表構築引数) {
        this._基準の時刻 = 引数.基準の時刻
        this._基準の通しステップ = 引数.基準の通しステップ
        this._拍毎分 = 引数.拍毎分
    }

    // 基準より前の通しステップは、既に過ぎているため時刻を答えられない。明示の失敗にする。
    public 通しステップの時刻(通しステップ: ステップ): 秒数 {
        const 差 = 通しステップ.数値() - this._基準の通しステップ.数値()
        if (差 < 0) {
            throw new Error(
                `基準より前の通しステップの時刻は求められません: 通しステップ=${通しステップ.数値()} 基準=${this._基準の通しステップ.数値()}`,
            )
        }
        return this._基準の時刻.足す(this._拍毎分.ステップ数の秒数(ステップ.生成する(差)))
    }

    // 音声の時計の時刻が、演奏を始めてから何ステップ目に当たるかを答える。
    public 時刻の通しステップ(時刻: 秒数): ステップ {
        if (時刻.より前か(this._基準の時刻)) {
            return this._基準の通しステップ
        }
        const 経過 = 時刻.差を求める(this._基準の時刻)
        return this._基準の通しステップ.足す(this._拍毎分.経過した秒数のステップ数(経過))
    }

    public 基準を置き直す(引数: 演奏の時刻表構築引数): void {
        this._基準の時刻 = 引数.基準の時刻
        this._基準の通しステップ = 引数.基準の通しステップ
        this._拍毎分 = 引数.拍毎分
    }

    public get 現在の拍毎分(): 拍毎分 {
        return this._拍毎分
    }

    public get 基準の通しステップ(): ステップ {
        return this._基準の通しステップ
    }
}
