import type { パターン, 打ち込みの対象, 楽曲 } from '../../../生成/編集資源契約.ts'
import { 初期楽曲を生成する } from './初期楽曲生成.ts'
import { 打ち込み先の行 } from './打ち込み先の行.ts'

// 楽曲の編集状態を一元管理する。
// パターンを1つも持たない楽曲が契約上成り立つため、選択中のパターンは未選択(null)を取りうる。
export class 楽曲編集状態 {
    public 楽曲: 楽曲
    public 選択中パターンの名乗り: string | null

    public constructor(初期楽曲?: 楽曲) {
        this.楽曲 = 初期楽曲 ? 楽曲編集状態.楽曲を複製する(初期楽曲) : 初期楽曲を生成する()
        this.選択中パターンの名乗り = null
        this.選択中パターンが失われていたら選び直す()
    }

    // 保存や外部連携のために現在の楽曲データの複製を取り出す。
    public 楽曲を取得する(): 楽曲 {
        return 楽曲編集状態.楽曲を複製する(this.楽曲)
    }

    public パターンを取得する(名乗り: string): パターン {
        const パターン = this.楽曲.パターン一覧.find((p) => p.名乗り === 名乗り)
        if (パターン === undefined) {
            throw new Error(`パターンが存在しません: ${名乗り}`)
        }
        return パターン
    }

    public パターンが存在するか(名乗り: string): boolean {
        return this.楽曲.パターン一覧.some((p) => p.名乗り === 名乗り)
    }

    public 選択中パターンを取得する(): パターン {
        if (this.選択中パターンの名乗り === null) {
            throw new Error('パターンが1つも無いため選択中のパターンを取得できません')
        }
        return this.パターンを取得する(this.選択中パターンの名乗り)
    }

    // 打点の操作コマンドと差し戻しが書き換える格子の1行を、指し先の実在を確かめてから貸す。
    public 打ち込み先の行を取得する(対象: 打ち込みの対象): 打ち込み先の行 {
        const パターン = this.パターンを取得する(対象.パターンの名乗り)
        const トラック格子 = パターン.格子[対象.トラックの位置]
        if (トラック格子 === undefined) {
            throw new Error(`格子のトラックがありません: パターン=${対象.パターンの名乗り} トラックの位置=${対象.トラックの位置}`)
        }
        const 行 = トラック格子.行一覧[対象.行の位置]
        if (行 === undefined) {
            throw new Error(`格子の行がありません: パターン=${対象.パターンの名乗り} トラックの位置=${対象.トラックの位置} 行の位置=${対象.行の位置}`)
        }
        return new 打ち込み先の行(行, 対象)
    }

    // 削除・差し戻し・上書きで選択中のパターンが消えたとき、先頭のパターンへ選択を移す。
    // パターンを1つも持たない楽曲では未選択にし、使う地点で失敗させる。
    public 選択中パターンが失われていたら選び直す(): void {
        if (this.選択中パターンの名乗り !== null && this.パターンが存在するか(this.選択中パターンの名乗り)) {
            return
        }
        const 先頭のパターン = this.楽曲.パターン一覧[0]
        this.選択中パターンの名乗り = 先頭のパターン === undefined ? null : 先頭のパターン.名乗り
    }

    public 状態を上書きする(新楽曲: 楽曲): void {
        this.楽曲 = 楽曲編集状態.楽曲を複製する(新楽曲)
        this.選択中パターンが失われていたら選び直す()
    }

    // 楽曲オブジェクト全体の完全なディープコピーを生成する。
    public static 楽曲を複製する(元楽曲: 楽曲): 楽曲 {
        return {
            形式版: 元楽曲.形式版,
            名乗り: 元楽曲.名乗り,
            表示名: 元楽曲.表示名,
            テンポ: 元楽曲.テンポ,
            トラック構成: 元楽曲.トラック構成.map((t) => ({
                表示名: t.表示名,
                種類: t.種類,
                音の並び:
                    t.音の並び.種類 === '音高の行一覧'
                        ? { 種類: '音高の行一覧', 値: [...t.音の並び.値] }
                        : { 種類: '打楽器の行一覧', 値: [...t.音の並び.値] },
                楽器: t.楽器,
                音量: t.音量,
                進行の割り当て: t.進行の割り当て ? { ...t.進行の割り当て } : null,
            })),
            ミキサー設定: { ...元楽曲.ミキサー設定 },
            独自進行一覧: 元楽曲.独自進行一覧.map((進行) => ({
                名前: 進行.名前,
                和音一覧: 進行.和音一覧.map((和音) => ({ ...和音 })),
            })),
            パターン一覧: 元楽曲.パターン一覧.map((p) => ({
                名乗り: p.名乗り,
                表示名: p.表示名,
                小節数: p.小節数,
                進行の参照: { ...p.進行の参照 },
                格子: p.格子.map((トラック格子) => ({
                    行一覧: トラック格子.行一覧.map((行) => [...行]),
                })),
            })),
            曲構成: 元楽曲.曲構成.map((節) => ({ ...節 })),
        }
    }
}
