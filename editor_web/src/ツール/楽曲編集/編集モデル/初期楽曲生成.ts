import type { 音の並び, 楽曲 } from '../../../生成/編集資源契約.ts'
import { 楽曲の形式版 } from '../../../生成/編集資源契約.ts'
import {
    既定のトラック構成一覧,
    既定のミキサー設定,
    トラック構成から空の格子一覧を生成する,
} from './既定のトラック構成.ts'

function 音の並びを複製する(並び: 音の並び): 音の並び {
    switch (並び.種類) {
        case '音高の行一覧':
            return { 種類: '音高の行一覧', 値: [...並び.値] }
        case '打楽器の行一覧':
            return { 種類: '打楽器の行一覧', 値: [...並び.値] }
    }
}

// 初期状態の楽曲を生成する。
export function 初期楽曲を生成する(
    名乗り: string = 'song-1',
    表示名: string = '新しい楽曲',
): 楽曲 {
    const 格子一覧 = トラック構成から空の格子一覧を生成する(既定のトラック構成一覧)
    return {
        形式版: 楽曲の形式版,
        名乗り,
        表示名,
        テンポ: 124,
        トラック構成: 既定のトラック構成一覧.map((t) => ({
            表示名: t.表示名,
            種類: t.種類,
            音の並び: 音の並びを複製する(t.音の並び),
            楽器: t.楽器,
            音量: t.音量,
            進行の割り当て: t.進行の割り当て ? { ...t.進行の割り当て } : null,
        })),
        ミキサー設定: { ...既定のミキサー設定 },
        独自進行一覧: [],
        パターン一覧: [
            {
                名乗り: 'pattern-1',
                表示名: 'パターン1',
                進行の参照: { 種類: '既定の進行', 識別子: '戦闘と道' },
                格子: 格子一覧,
            },
        ],
        曲構成: [],
    }
}
