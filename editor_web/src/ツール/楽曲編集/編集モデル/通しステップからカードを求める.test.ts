import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import { type パターン, type 曲の節 } from '../../../生成/編集資源契約.ts'
import { 曲構成をカードの列へ展開する } from './曲構成のカード列.ts'
import { ステップ } from './演奏の時刻/index.ts'
import { 通しステップからカードを求める } from './通しステップからカードを求める.ts'

function パターンを作る(名乗り: string, 小節数: number): パターン {
    return {
        名乗り,
        表示名: 名乗り,
        小節数,
        進行の参照: { 種類: '既定の進行', 識別子: '街とやすらぎ' },
        格子: [],
    }
}

describe('通しステップからカードを求めるテスト', () => {
    it('カードの列が空なら null を返すこと', () => {
        assert.equal(通しステップからカードを求める([], ステップ.ゼロ()), null)
    })

    it('小節数が揃ったA(2小節)×2, B(2小節)×1で、通しステップ70はB1枚目のカード(5枚目)の6ステップ目になること', () => {
        const パターン一覧 = [パターンを作る('A', 2), パターンを作る('B', 2)]
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'A', 繰り返し回数: 2 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
        ]
        const カード列 = 曲構成をカードの列へ展開する(曲構成, パターン一覧)

        const 結果 = 通しステップからカードを求める(カード列, ステップ.生成する(70))

        assert.notEqual(結果, null)
        assert.equal(結果?.カードの添字, 4)
        assert.equal(結果?.カード内ステップ.数値(), 6)
        assert.equal(カード列[4].パターンの名乗り, 'B')
    })

    it('曲を1周した後の通しステップ100は、1枚目のカードの4ステップ目へ戻ること', () => {
        const パターン一覧 = [パターンを作る('A', 2), パターンを作る('B', 2)]
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'A', 繰り返し回数: 2 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
        ]
        const カード列 = 曲構成をカードの列へ展開する(曲構成, パターン一覧)
        assert.equal(カード列.length, 6)

        const 結果 = 通しステップからカードを求める(カード列, ステップ.生成する(100))

        assert.notEqual(結果, null)
        assert.equal(結果?.カードの添字, 0)
        assert.equal(結果?.カード内ステップ.数値(), 4)
    })

    it('小節数が節ごとに違うA(2小節)×2, B(1小節)×1, C(4小節)×1で、通しステップ100が正しいカードとカード内ステップへ解決されること', () => {
        const パターン一覧 = [パターンを作る('A', 2), パターンを作る('B', 1), パターンを作る('C', 4)]
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'A', 繰り返し回数: 2 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
            { パターンの名乗り: 'C', 繰り返し回数: 1 },
        ]
        const カード列 = 曲構成をカードの列へ展開する(曲構成, パターン一覧)
        assert.equal(カード列.length, 9)

        const 結果 = 通しステップからカードを求める(カード列, ステップ.生成する(100))

        assert.notEqual(結果, null)
        assert.equal(結果?.カードの添字, 6)
        assert.equal(結果?.カード内ステップ.数値(), 4)
        assert.equal(カード列[6].パターンの名乗り, 'C')
        assert.equal(カード列[6].曲全体での小節番号, 7)
    })
})
