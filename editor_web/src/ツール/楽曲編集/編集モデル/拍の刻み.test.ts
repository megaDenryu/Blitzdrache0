import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 小節あたりのステップ数 } from '../../../生成/編集資源契約.ts'
import { ステップ, 拍あたりのステップ数, 通しステップの拍の位置づけを求める } from './演奏の時刻/index.ts'

// 拍の位置づけは小節の頭を「拍の番号を小節あたりの拍数で割り切れるか」で数える。
// ここでは契約の小節あたりのステップ数だけを物差しにして同じ判定を突き合わせ、
// 拍あたりのステップ数・小節あたりの拍数・契約の3つの関係が崩れたら落ちるようにする。
describe('拍の刻み', () => {
    it('小節の頭と判定される通しステップが、契約の小節あたりのステップ数の倍数とちょうど一致すること', () => {
        for (let 番号 = 0; 番号 < 小節あたりのステップ数 * 3; 番号++) {
            const 位置づけ = 通しステップの拍の位置づけを求める(ステップ.生成する(番号))
            assert.equal(位置づけ === '小節の頭', 番号 % 小節あたりのステップ数 === 0, `通しステップ${番号}の位置づけ=${位置づけ}`)
            assert.equal(位置づけ !== '拍の頭でない', 番号 % 拍あたりのステップ数 === 0, `通しステップ${番号}の位置づけ=${位置づけ}`)
        }
    })
})
