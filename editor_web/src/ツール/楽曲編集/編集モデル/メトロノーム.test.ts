import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { メトロノームの入切 } from './メトロノームの入切.ts'
import {
    ステップ,
    テンポ,
    通しステップの拍の位置づけを求める,
    秒数,
    演奏の時刻表,
    type 拍の位置づけ,
} from './演奏の時刻/index.ts'

const 浮動小数の丸めの許容 = 1e-9

// 通しステップの列のうち拍の頭だけを、位置づけと一緒に取り出す。
function 拍の頭を拾う(ステップ数: number): { 通しステップ: ステップ; 位置づけ: 拍の位置づけ }[] {
    const 拾ったもの: { 通しステップ: ステップ; 位置づけ: 拍の位置づけ }[] = []
    for (let 番号 = 0; 番号 < ステップ数; 番号++) {
        const 通しステップ = ステップ.生成する(番号)
        const 位置づけ = 通しステップの拍の位置づけを求める(通しステップ)
        if (位置づけ !== '拍の頭でない') 拾ったもの.push({ 通しステップ, 位置づけ })
    }
    return 拾ったもの
}

describe('メトロノーム', () => {
    it('拍の頭の時刻の列が 60 ÷ テンポ を公差とする等差数列になること', () => {
        for (const 値 of [40, 110, 300]) {
            const 時刻表 = new 演奏の時刻表({
                基準の時刻: 秒数.生成する(0.5),
                基準の通しステップ: ステップ.ゼロ(),
                テンポ: テンポ.生成する(値),
            })
            const 拍の時刻 = 拍の頭を拾う(128).map((拍) => 時刻表.通しステップの時刻(拍.通しステップ).数値())
            assert.strictEqual(拍の時刻.length, 32, `テンポ=${値}`)
            assert.ok(Math.abs(拍の時刻[0] - 0.5) < 浮動小数の丸めの許容, `テンポ=${値}の最初の拍`)
            for (let 番号 = 1; 番号 < 拍の時刻.length; 番号++) {
                const 差 = 拍の時刻[番号] - 拍の時刻[番号 - 1]
                assert.ok(Math.abs(差 - 60 / 値) < 浮動小数の丸めの許容, `テンポ=${値}の${番号}拍目の差=${差}`)
            }
        }
    })

    it('小節の頭が4拍ごとに来ること', () => {
        const 拍の一覧 = 拍の頭を拾う(128)
        for (const [拍番号, 拍] of 拍の一覧.entries()) {
            const 期待 = 拍番号 % 4 === 0 ? '小節の頭' : '小節の中の拍'
            assert.strictEqual(拍.位置づけ, 期待, `${拍番号}拍目(通しステップ${拍.通しステップ.数値()})`)
        }
    })

    it('拍の頭は4ステップごとに来て、その間のステップでは鳴らさないこと', () => {
        for (const [拍番号, 拍] of 拍の頭を拾う(128).entries()) {
            assert.strictEqual(拍.通しステップ.数値(), 拍番号 * 4)
        }
        for (const 番号 of [1, 2, 3, 5, 15, 17, 127]) {
            assert.strictEqual(通しステップの拍の位置づけを求める(ステップ.生成する(番号)), '拍の頭でない')
        }
    })

    it('入切の切り替えが状態を変えること', () => {
        const 入切 = new メトロノームの入切()
        assert.strictEqual(入切.入っているか, false)
        入切.切り替える()
        assert.strictEqual(入切.入っているか, true)
        入切.切り替える()
        assert.strictEqual(入切.入っているか, false)
    })
})
