import {
    パターンのステップ数 as 既定パターンのステップ数,
} from '../../../生成/編集資源契約.ts'
import { ステップ } from './演奏の時刻/index.ts'
import type { 曲構成のカード } from './曲構成のカード列.ts'

// 通しステップが、カードの列の何枚目の何ステップ目に当たるかの答え。
export type カードのステップ位置 = {
    readonly カードの添字: number
    readonly カード内ステップ: ステップ
}

// 通しステップから、それが当たるカードとカード内ステップを求める。
// 演奏はカードの列の全体の長さで1周した後も先頭へ戻るため、剰余はステップが持つ折り返しで取る。
// カードの列が空のときは無言で0番目を返さず、答えが無いことを null で表す。
export function 通しステップからカードを求める(
    カードの列: readonly 曲構成のカード[],
    通しステップ: ステップ,
    パターンのステップ数: number = 既定パターンのステップ数,
): カードのステップ位置 | null {
    if (カードの列.length === 0) {
        return null
    }
    const 全体の長さ = ステップ.生成する(カードの列.length * パターンのステップ数)
    const 折り返した通しステップ = 通しステップ.全体の長さで折り返す(全体の長さ)
    const カードの添字 = Math.floor(折り返した通しステップ.数値() / パターンのステップ数)
    return {
        カードの添字,
        カード内ステップ: ステップ.生成する(折り返した通しステップ.数値() % パターンのステップ数),
    }
}
