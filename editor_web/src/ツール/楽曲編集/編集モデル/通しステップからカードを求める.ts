import { ステップ, 小節あたりのステップ数 } from './演奏の時刻/index.ts'
import type { 曲構成のカード } from './曲構成のカード列.ts'

// 通しステップが、カードの列の何枚目の何ステップ目に当たるかの答え。
export type カードのステップ位置 = {
    readonly カードの添字: number
    readonly カード内ステップ: ステップ
}

// 通しステップから、それが当たるカードとカード内ステップを求める。
// カード1枚は必ず1小節(小節あたりのステップ数)だが、カードが属するパターンの小節数は節ごとに違うため、
// 全体の長さは最後のカードの始まりから1小節分足して求め、当たるカードは各カードの始まりの通しステップから逆算する。
// 演奏はカードの列の全体の長さで1周した後も先頭へ戻るため、剰余はステップが持つ折り返しで取る。
// カードの列が空のときは無言で0番目を返さず、答えが無いことを null で表す。
export function 通しステップからカードを求める(
    カードの列: readonly 曲構成のカード[],
    通しステップ: ステップ,
): カードのステップ位置 | null {
    if (カードの列.length === 0) {
        return null
    }
    const 最後のカード = カードの列[カードの列.length - 1]
    const 全体の長さ = ステップ.生成する(最後のカード.始まりの通しステップ.数値() + 小節あたりのステップ数)
    const 折り返した通しステップ = 通しステップ.全体の長さで折り返す(全体の長さ)
    const カードの添字 = カードの列.findLastIndex(
        (カード) => カード.始まりの通しステップ.数値() <= 折り返した通しステップ.数値(),
    )
    const 対象カード = カードの列[カードの添字]
    return {
        カードの添字,
        カード内ステップ: ステップ.生成する(折り返した通しステップ.数値() - 対象カード.始まりの通しステップ.数値()),
    }
}
