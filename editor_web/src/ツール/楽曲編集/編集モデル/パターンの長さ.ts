import { 小節あたりのステップ数, type パターン } from '../../../生成/編集資源契約.ts'

// パターンの小節数から、その小節数ぶんの格子が並べるステップ数を求める。
// 正本は「小節数×小節あたりのステップ数」という判断16の式であり、この関数だけが計算する。
export function 小節数からステップ数を求める(小節数: number): number {
    return 小節数 * 小節あたりのステップ数
}

// パターンの格子が持つステップ数を求める。パターンの小節数から導く唯一の入口である。
export function パターンのステップ数を求める(対象のパターン: パターン): number {
    return 小節数からステップ数を求める(対象のパターン.小節数)
}
