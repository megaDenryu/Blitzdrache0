import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import { パターンのステップ数, type 和音, type 和音の種類 } from '../../../生成/編集資源契約.ts'
import {
    あるステップの和音を取得する,
    進行の帯の区切り一覧を計算する,
    和音の表示名を組み立てる,
    和音が許す音のピッチクラス一覧,
} from './音楽理論.ts'

describe('音楽理論のテスト', () => {
    it('8種類の和音×12の根音の全96通りで許す音のピッチクラスが手計算の期待値と一致すること', () => {
        const 和音種類ごとの手計算音程: Record<和音の種類, readonly number[]> = {
            長三和音: [0, 4, 7], 短三和音: [0, 3, 7],
            長七の和音: [0, 4, 7, 11], 短七の和音: [0, 3, 7, 10],
            属七の和音: [0, 4, 7, 10], 四度掛留の和音: [0, 5, 7],
            減三和音: [0, 3, 6], 増三和音: [0, 4, 8],
        }
        const 和音種類一覧: readonly 和音の種類[] = [
            '長三和音', '短三和音', '長七の和音', '短七の和音',
            '属七の和音', '四度掛留の和音', '減三和音', '増三和音',
        ]
        for (const 種類 of 和音種類一覧) {
            const 音程一覧 = 和音種類ごとの手計算音程[種類]
            for (let 根音 = 0; 根音 < 12; 根音++) {
                const 対象の和音: 和音 = { 根音, 種類, 続くステップ数: 4 }
                const 実際 = 和音が許す音のピッチクラス一覧(対象の和音)
                const 期待値 = 音程一覧.map((iv) => (根音 + iv) % 12)
                assert.deepEqual(実際, 期待値, `${根音} ${種類} のピッチクラスが一致すること`)
            }
        }
    })

    it('代表的な和音名が正しく組み立てられること', () => {
        assert.equal(和音の表示名を組み立てる({ 根音: 0, 種類: '長三和音', 続くステップ数: 4 }), 'C')
        assert.equal(和音の表示名を組み立てる({ 根音: 9, 種類: '短三和音', 続くステップ数: 4 }), 'Am')
        assert.equal(和音の表示名を組み立てる({ 根音: 7, 種類: '属七の和音', 続くステップ数: 4 }), 'G7')
        assert.equal(和音の表示名を組み立てる({ 根音: 6, 種類: '長七の和音', 続くステップ数: 4 }), 'F#M7')
        assert.equal(和音の表示名を組み立てる({ 根音: 2, 種類: '短七の和音', 続くステップ数: 4 }), 'Dm7')
        assert.equal(和音の表示名を組み立てる({ 根音: 4, 種類: '四度掛留の和音', 続くステップ数: 4 }), 'Esus4')
        assert.equal(和音の表示名を組み立てる({ 根音: 11, 種類: '減三和音', 続くステップ数: 4 }), 'Bdim')
        assert.equal(和音の表示名を組み立てる({ 根音: 0, 種類: '増三和音', 続くステップ数: 4 }), 'Caug')
    })

    it('ステップから和音への写像が周回および打ち切りを含めて正しく動作すること', () => {
        const 短い進行: 和音[] = [
            { 根音: 0, 種類: '長三和音', 続くステップ数: 4 },
            { 根音: 9, 種類: '短三和音', 続くステップ数: 4 },
            { 根音: 5, 種類: '長三和音', 続くステップ数: 4 },
            { 根音: 7, 種類: '長三和音', 続くステップ数: 4 },
        ]
        assert.equal(あるステップの和音を取得する(短い進行, 0).根音, 0)
        assert.equal(あるステップの和音を取得する(短い進行, 3).根音, 0)
        assert.equal(あるステップの和音を取得する(短い進行, 4).根音, 9)
        assert.equal(あるステップの和音を取得する(短い進行, 15).根音, 7)
        assert.equal(あるステップの和音を取得する(短い進行, 16).根音, 0)
        assert.equal(あるステップの和音を取得する(短い進行, 20).根音, 9)
    })

    it('進行の帯の区切り一覧がパターンのステップ数を埋め周回フラグを正しく設定すること', () => {
        const 短い進行: 和音[] = [
            { 根音: 0, 種類: '長三和音', 続くステップ数: 4 },
            { 根音: 9, 種類: '短三和音', 続くステップ数: 4 },
        ]
        const 区切り一覧 = 進行の帯の区切り一覧を計算する(短い進行, パターンのステップ数)
        assert.equal(区切り一覧.length, 8)
        assert.equal(区切り一覧.reduce((sum, r) => sum + r.ステップ幅, 0), パターンのステップ数)
        assert.equal(区切り一覧[0]?.周回後か, false)
        assert.equal(区切り一覧[1]?.周回後か, false)
        assert.equal(区切り一覧[2]?.周回後か, true)
        assert.equal(区切り一覧[7]?.周回後か, true)

        const 半端な進行: 和音[] = [
            { 根音: 0, 種類: '長三和音', 続くステップ数: 6 },
            { 根音: 7, 種類: '長三和音', 続くステップ数: 6 },
            { 根音: 9, 種類: '短三和音', 続くステップ数: 6 },
        ]
        const 半端区切り一覧 = 進行の帯の区切り一覧を計算する(半端な進行, パターンのステップ数)
        assert.equal(半端区切り一覧.reduce((sum, r) => sum + r.ステップ幅, 0), パターンのステップ数)
        assert.equal(半端区切り一覧[0]?.ステップ幅, 6)
        assert.equal(半端区切り一覧[0]?.周回後か, false)
        assert.equal(半端区切り一覧[1]?.ステップ幅, 6)
        assert.equal(半端区切り一覧[1]?.周回後か, false)
        assert.equal(半端区切り一覧[2]?.ステップ幅, 6)
        assert.equal(半端区切り一覧[2]?.周回後か, false)
        assert.equal(半端区切り一覧[3]?.ステップ幅, 6)
        assert.equal(半端区切り一覧[3]?.周回後か, true)
        assert.equal(半端区切り一覧[4]?.ステップ幅, 6)
        assert.equal(半端区切り一覧[4]?.周回後か, true)
        assert.equal(半端区切り一覧[5]?.ステップ幅, 2)
        assert.equal(半端区切り一覧[5]?.周回後か, true)
    })
})
