// 指定した行数とステップ数を持つ空のトラック格子を生成する。
export function 空のトラック格子を生成する(行数: number, ステップ数: number = パターンのステップ数): トラックの格子 {
    const 行一覧: number[][] = []
    for (let i = 0; i < 行数; i++) {
        行一覧.push(new Array(ステップ数).fill(0))
    }
    return { 行一覧 }
}

// トラック構成に合わせて全トラック分の空の格子を生成する。
export function トラック構成から空の格子一覧を生成する(
    トラック構成: readonly トラック定義[],
    ステップ数: number = パターンのステップ数,
): トラックの格子[] {
    return トラック構成.map((トラック) => {
        const 行数 = トラック.音の並び.値.length
        return 空のトラック格子を生成する(行数, ステップ数)
    })
}
