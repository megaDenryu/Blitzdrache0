import type { パターン } from '../../../生成/編集資源契約.ts'

// 曲構成の節や演奏の範囲がパターンの名乗りだけを持つ地点から、パターン一覧の中の実体を引き当てる。
// 曲構成が指すパターンの名乗りが実在しないのは配線の誤りであるため、明示の失敗にする。
export function 名乗りでパターンを探す(パターン一覧: readonly パターン[], 名乗り: string): パターン {
    const パターン = パターン一覧.find((候補) => 候補.名乗り === 名乗り)
    if (パターン === undefined) {
        throw new Error(`パターンが存在しません: 名乗り=${名乗り}`)
    }
    return パターン
}
