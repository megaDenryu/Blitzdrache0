import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import { パターンのステップ数, type 曲の節 } from '../../../生成/編集資源契約.ts'
import { 曲全体のステップ数を計算する, 曲のステップ位置を解決する } from './曲構成の計算.ts'

describe('曲構成の計算と位置解決のテスト', () => {
    it('曲構成が空のときは曲全体のステップ数が0になり、開いているパターンをループすること', () => {
        const 空曲構成: 曲の節[] = []
        assert.equal(曲全体のステップ数を計算する(空曲構成), 0)

        const 位置0 = 曲のステップ位置を解決する(空曲構成, 0, 'pat-a')
        assert.deepEqual(位置0, { パターンの名乗り: 'pat-a', パターン内ステップ: 0 })

        const 位置35 = 曲のステップ位置を解決する(空曲構成, パターンのステップ数 + 3, 'pat-a')
        assert.deepEqual(位置35, { パターンの名乗り: 'pat-a', パターン内ステップ: 3 })
    })

    it('複数パターンと繰り返しを含む曲構成で正しくステップ位置が解決されること', () => {
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'intro', 繰り返し回数: 1 },
            { パターンの名乗り: 'verse', 繰り返し回数: 2 },
            { パターンの名乗り: 'chorus', 繰り返し回数: 1 },
        ]
        const 全体ステップ数 = パターンのステップ数 * 4
        assert.equal(曲全体のステップ数を計算する(曲構成), 全体ステップ数)

        // intro の範囲
        assert.deepEqual(曲のステップ位置を解決する(曲構成, 0, 'dummy'), {
            パターンの名乗り: 'intro',
            パターン内ステップ: 0,
        })
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターンのステップ数 - 1, 'dummy'), {
            パターンの名乗り: 'intro',
            パターン内ステップ: 31,
        })

        // verse 1周目
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターンのステップ数, 'dummy'), {
            パターンの名乗り: 'verse',
            パターン内ステップ: 0,
        })
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターンのステップ数 * 2 - 1, 'dummy'), {
            パターンの名乗り: 'verse',
            パターン内ステップ: 31,
        })

        // verse 2周目
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターンのステップ数 * 2, 'dummy'), {
            パターンの名乗り: 'verse',
            パターン内ステップ: 0,
        })
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターンのステップ数 * 3 - 1, 'dummy'), {
            パターンの名乗り: 'verse',
            パターン内ステップ: 31,
        })

        // chorus
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターンのステップ数 * 3, 'dummy'), {
            パターンの名乗り: 'chorus',
            パターン内ステップ: 0,
        })
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターンのステップ数 * 4 - 1, 'dummy'), {
            パターンの名乗り: 'chorus',
            パターン内ステップ: 31,
        })

        // 全体周回後
        assert.deepEqual(曲のステップ位置を解決する(曲構成, 全体ステップ数, 'dummy'), {
            パターンの名乗り: 'intro',
            パターン内ステップ: 0,
        })
    })
})
