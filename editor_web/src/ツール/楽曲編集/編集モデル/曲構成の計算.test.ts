import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import { type パターン as 契約パターン, type 曲の節 } from '../../../生成/編集資源契約.ts'
import { 曲全体のステップ数を計算する, 曲のステップ位置を解決する } from './曲構成の計算.ts'

function パターンを作る(名乗り: string, 小節数: number): 契約パターン {
    return {
        名乗り,
        表示名: 名乗り,
        小節数,
        進行の参照: { 種類: '既定の進行', 識別子: '街とやすらぎ' },
        格子: [],
    }
}

describe('曲構成の計算と位置解決のテスト', () => {
    it('曲構成が空のときは曲全体のステップ数が0になり、開いているパターン自身の長さで折り返すこと', () => {
        const パターン一覧 = [パターンを作る('pat-a', 2)]
        const 空曲構成: 曲の節[] = []
        assert.equal(曲全体のステップ数を計算する(空曲構成, パターン一覧), 0)

        const 位置0 = 曲のステップ位置を解決する(空曲構成, パターン一覧, 0, 'pat-a')
        assert.deepEqual(位置0, { パターンの名乗り: 'pat-a', パターン内ステップ: 0 })

        const 位置35 = 曲のステップ位置を解決する(空曲構成, パターン一覧, 32 + 3, 'pat-a')
        assert.deepEqual(位置35, { パターンの名乗り: 'pat-a', パターン内ステップ: 3 })
    })

    it('小節数が揃った複数パターンと繰り返しを含む曲構成で正しくステップ位置が解決されること', () => {
        const パターン一覧 = [パターンを作る('intro', 2), パターンを作る('verse', 2), パターンを作る('chorus', 2)]
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'intro', 繰り返し回数: 1 },
            { パターンの名乗り: 'verse', 繰り返し回数: 2 },
            { パターンの名乗り: 'chorus', 繰り返し回数: 1 },
        ]
        const 全体ステップ数 = 32 * 4
        assert.equal(曲全体のステップ数を計算する(曲構成, パターン一覧), 全体ステップ数)

        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターン一覧, 0, 'dummy'), {
            パターンの名乗り: 'intro',
            パターン内ステップ: 0,
        })
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターン一覧, 31, 'dummy'), {
            パターンの名乗り: 'intro',
            パターン内ステップ: 31,
        })
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターン一覧, 32, 'dummy'), {
            パターンの名乗り: 'verse',
            パターン内ステップ: 0,
        })
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターン一覧, 95, 'dummy'), {
            パターンの名乗り: 'verse',
            パターン内ステップ: 31,
        })
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターン一覧, 96, 'dummy'), {
            パターンの名乗り: 'chorus',
            パターン内ステップ: 0,
        })
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターン一覧, 全体ステップ数, 'dummy'), {
            パターンの名乗り: 'intro',
            パターン内ステップ: 0,
        })
    })

    it('小節数が節ごとに違う曲構成A(2小節)×2, B(1小節)×1, C(4小節)×1で全体ステップ数が144になり、各節の境界が正しく解決されること', () => {
        const パターン一覧 = [パターンを作る('A', 2), パターンを作る('B', 1), パターンを作る('C', 4)]
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'A', 繰り返し回数: 2 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
            { パターンの名乗り: 'C', 繰り返し回数: 1 },
        ]
        assert.equal(曲全体のステップ数を計算する(曲構成, パターン一覧), 144)

        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターン一覧, 0, 'dummy'), {
            パターンの名乗り: 'A',
            パターン内ステップ: 0,
        })
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターン一覧, 63, 'dummy'), {
            パターンの名乗り: 'A',
            パターン内ステップ: 31,
        })
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターン一覧, 64, 'dummy'), {
            パターンの名乗り: 'B',
            パターン内ステップ: 0,
        })
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターン一覧, 79, 'dummy'), {
            パターンの名乗り: 'B',
            パターン内ステップ: 15,
        })
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターン一覧, 80, 'dummy'), {
            パターンの名乗り: 'C',
            パターン内ステップ: 0,
        })
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターン一覧, 143, 'dummy'), {
            パターンの名乗り: 'C',
            パターン内ステップ: 63,
        })
        assert.deepEqual(曲のステップ位置を解決する(曲構成, パターン一覧, 144, 'dummy'), {
            パターンの名乗り: 'A',
            パターン内ステップ: 0,
        })
    })
})
