import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { ステップ, テンポ, 秒数, 演奏の時刻表 } from './演奏の時刻/index.ts'

const 浮動小数の丸めの許容 = 1e-9

describe('演奏の時刻', () => {
    it('ステップ1つ分の秒数が 60 ÷ テンポ ÷ 4 と一致すること', () => {
        for (const 値 of [40, 90, 110, 124, 300]) {
            const 実際 = テンポ.生成する(値).ステップ1つ分の秒数().数値()
            assert.ok(Math.abs(実際 - 60 / 値 / 4) < 浮動小数の丸めの許容, `テンポ=${値}`)
        }
    })

    it('ステップ数の秒数がステップ1つ分の秒数の整数倍になること', () => {
        const 速さ = テンポ.生成する(120)
        const ひとつ分 = 速さ.ステップ1つ分の秒数().数値()
        assert.ok(Math.abs(速さ.ステップ数の秒数(ステップ.生成する(16)).数値() - ひとつ分 * 16) < 浮動小数の丸めの許容)
    })

    it('範囲の外のテンポと負のステップを拒むこと', () => {
        assert.throws(() => テンポ.生成する(39))
        assert.throws(() => テンポ.生成する(301))
        assert.throws(() => テンポ.生成する(120.5))
        assert.throws(() => ステップ.生成する(-1))
        assert.throws(() => 秒数.生成する(-0.1))
    })

    it('予約される時刻の列が 60 ÷ テンポ ÷ 4 を公差とする等差数列になること', () => {
        const 速さ = テンポ.生成する(110)
        const 時刻表 = new 演奏の時刻表({
            基準の時刻: 秒数.生成する(1.25),
            基準の通しステップ: ステップ.ゼロ(),
            テンポ: 速さ,
        })
        const 時刻の列: number[] = []
        for (let 番号 = 0; 番号 < 64; 番号++) {
            時刻の列.push(時刻表.通しステップの時刻(ステップ.生成する(番号)).数値())
        }
        const 公差 = 60 / 110 / 4
        assert.ok(Math.abs(時刻の列[0] - 1.25) < 浮動小数の丸めの許容)
        for (let 番号 = 1; 番号 < 時刻の列.length; 番号++) {
            const 差 = 時刻の列[番号] - 時刻の列[番号 - 1]
            assert.ok(Math.abs(差 - 公差) < 浮動小数の丸めの許容, `${番号}番目の差=${差}`)
        }
    })

    it('時刻から通しステップを求める向きが、ステップから時刻を求める向きと噛み合うこと', () => {
        const 時刻表 = new 演奏の時刻表({
            基準の時刻: 秒数.生成する(2),
            基準の通しステップ: ステップ.ゼロ(),
            テンポ: テンポ.生成する(124),
        })
        for (const 番号 of [0, 1, 7, 31, 63]) {
            const 時刻 = 時刻表.通しステップの時刻(ステップ.生成する(番号))
            assert.strictEqual(時刻表.時刻の通しステップ(時刻).数値(), 番号)
        }
    })

    it('基準より前の時刻では基準のステップを返し、基準より前のステップの時刻は拒むこと', () => {
        const 時刻表 = new 演奏の時刻表({
            基準の時刻: 秒数.生成する(5),
            基準の通しステップ: ステップ.生成する(10),
            テンポ: テンポ.生成する(120),
        })
        assert.strictEqual(時刻表.時刻の通しステップ(秒数.生成する(1)).数値(), 10)
        assert.throws(() => 時刻表.通しステップの時刻(ステップ.生成する(9)))
    })
})
