// 楽器の名前から、その楽器が鳴らすものの定義を求める。
export function 楽器の音色を求める(対象の楽器: 楽器): 楽器の音色 {
    const 音色 = 楽器ごとの音色[対象の楽器]
    if (音色 === undefined) {
        throw new Error(`楽器の音色が定義されていません: ${対象の楽器}`)
    }
    return 音色
}

