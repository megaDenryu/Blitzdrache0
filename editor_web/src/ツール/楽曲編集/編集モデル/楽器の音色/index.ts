// 楽器の音の種類とは、楽器が音高を持つ音源か打楽器の音源かの区別のことである。値の名前はRustの正本
// `楽器の音の種類`(crates/editor_server/src/resource/music/instrument.rs)と揃え、区別そのものは別の表を持たずに
// 上の音色の対応表の鳴らし方から導く。楽器を足せば対応表の網羅でコンパイルが落ちるため、区別も必ず追随する。
type 楽器の音の種類 = '音高' | '打楽器'

function 楽器の音の種類を得る(対象の楽器: 楽器): 楽器の音の種類 {
    const 音色 = 楽器の音色を求める(対象の楽器)
    switch (音色.種類) {
        case '音高を鳴らす':
            return '音高'
        case '打楽器を鳴らす':
            return '打楽器'
    }
}

// 音の並びが受け入れる楽器の音の種類を得る。Rustの`音の並び::音の種類を得る`と同じ対応である(判断17)。
function 音の並びが受け入れる楽器の音の種類を得る(音の並びの種類: 音の並び['種類']): 楽器の音の種類 {
    switch (音の並びの種類) {
        case '音高の行一覧':
            return '音高'
        case '打楽器の行一覧':
            return '打楽器'
    }
}

// 音の並びへ割り当てられる楽器を、契約の楽器の並び順のまま返す(判断17)。
export function 音の並びへ割り当てられる楽器一覧を求める(音の並びの種類: 音の並び['種類']): readonly 楽器[] {
    const 受け入れる種類 = 音の並びが受け入れる楽器の音の種類を得る(音の並びの種類)
    return 音色を持つ楽器一覧.filter((楽器名) => 楽器の音の種類を得る(楽器名) === 受け入れる種類)
}
