import {
    パターンのステップ数 as 既定パターンのステップ数,
    type 曲の節,
} from '../../../生成/編集資源契約.ts'

// 曲全体のステップ数を計算する。曲構成が空なら0（現在開いているパターンのみループ）を返す。
export function 曲全体のステップ数を計算する(
    曲構成: readonly 曲の節[],
    パターンのステップ数: number = 既定パターンのステップ数,
): number {
    if (曲構成.length === 0) {
        return 0
    }
    return 曲構成.reduce((合計, 節) => 合計 + パターンのステップ数 * 節.繰り返し回数, 0)
}

export type 曲の再生位置 = {
    readonly パターンの名乗り: string
    readonly パターン内ステップ: number
}

// 曲全体のステップ位置から、どのパターンの何ステップ目かを解決する。
export function 曲のステップ位置を解決する(
    曲構成: readonly 曲の節[],
    曲ステップ: number,
    開いているパターンの名乗り: string,
    パターンのステップ数: number = 既定パターンのステップ数,
): 曲の再生位置 {
    if (曲構成.length === 0) {
        const ステップ = ((曲ステップ % パターンのステップ数) + パターンのステップ数) % パターンのステップ数
        return {
            パターンの名乗り: 開いているパターンの名乗り,
            パターン内ステップ: ステップ,
        }
    }
    const 全体ステップ数 = 曲全体のステップ数を計算する(曲構成, パターンのステップ数)
    let 残りステップ = ((曲ステップ % 全体ステップ数) + 全体ステップ数) % 全体ステップ数
    for (const 節 of 曲構成) {
        const 節のステップ数 = パターンのステップ数 * 節.繰り返し回数
        if (残りステップ < 節のステップ数) {
            return {
                パターンの名乗り: 節.パターンの名乗り,
                パターン内ステップ: 残りステップ % パターンのステップ数,
            }
        }
        残りステップ -= 節のステップ数
    }
    const 最後の節 = 曲構成[曲構成.length - 1]
    return {
        パターンの名乗り: 最後の節.パターンの名乗り,
        パターン内ステップ: 0,
    }
}
