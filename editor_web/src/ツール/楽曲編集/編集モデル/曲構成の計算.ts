import { type 曲の節, type パターン } from '../../../生成/編集資源契約.ts'
import { パターンのステップ数を求める } from './パターンの長さ.ts'
import { 名乗りでパターンを探す } from './パターンを探す.ts'

// 曲全体のステップ数を計算する。節ごとにパターンの小節数が違うため、節が指すパターンをその都度引き当てて数える。
// 曲構成が空なら0（現在開いているパターンのみループ）を返す。
export function 曲全体のステップ数を計算する(
    曲構成: readonly 曲の節[],
    パターン一覧: readonly パターン[],
): number {
    return 曲構成.reduce((合計, 節) => {
        const パターン = 名乗りでパターンを探す(パターン一覧, 節.パターンの名乗り)
        return 合計 + パターンのステップ数を求める(パターン) * 節.繰り返し回数
    }, 0)
}

export type 曲の再生位置 = {
    readonly パターンの名乗り: string
    readonly パターン内ステップ: number
}

// 曲全体のステップ位置から、どのパターンの何ステップ目かを解決する。
// 曲構成が空のときは、開いているパターン自身の長さで折り返す。
export function 曲のステップ位置を解決する(
    曲構成: readonly 曲の節[],
    パターン一覧: readonly パターン[],
    曲ステップ: number,
    開いているパターンの名乗り: string,
): 曲の再生位置 {
    if (曲構成.length === 0) {
        const 開いているパターン = 名乗りでパターンを探す(パターン一覧, 開いているパターンの名乗り)
        const パターンのステップ数 = パターンのステップ数を求める(開いているパターン)
        const ステップ = ((曲ステップ % パターンのステップ数) + パターンのステップ数) % パターンのステップ数
        return {
            パターンの名乗り: 開いているパターンの名乗り,
            パターン内ステップ: ステップ,
        }
    }
    const 全体ステップ数 = 曲全体のステップ数を計算する(曲構成, パターン一覧)
    let 残りステップ = ((曲ステップ % 全体ステップ数) + 全体ステップ数) % 全体ステップ数
    for (const 節 of 曲構成) {
        const パターン = 名乗りでパターンを探す(パターン一覧, 節.パターンの名乗り)
        const 節のパターンステップ数 = パターンのステップ数を求める(パターン)
        const 節のステップ数 = 節のパターンステップ数 * 節.繰り返し回数
        if (残りステップ < 節のステップ数) {
            return {
                パターンの名乗り: 節.パターンの名乗り,
                パターン内ステップ: 残りステップ % 節のパターンステップ数,
            }
        }
        残りステップ -= 節のステップ数
    }
    const 最後の節 = 曲構成[曲構成.length - 1]
    return {
        パターンの名乗り: 最後の節.パターンの名乗り,
        パターン内ステップ: 0,
    }
}
