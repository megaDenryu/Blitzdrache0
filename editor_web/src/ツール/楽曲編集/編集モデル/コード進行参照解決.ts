import type {
    コード進行,
    コード進行参照,
    トラック定義,
    和音,
} from '../../../生成/編集資源契約.ts'
import { 既定のコード進行一覧 } from '../../../生成/編集資源契約.ts'

// コード進行参照（既定・独自）から和音一覧を解決する。見つからない場合は明示の失敗にする。
export function コード進行参照から和音一覧を解決する(
    参照: コード進行参照,
    独自進行一覧: readonly コード進行[],
): readonly 和音[] {
    switch (参照.種類) {
        case '既定の進行': {
            const 既定進行 = 既定のコード進行一覧.find((進行) => 進行.識別子 === 参照.識別子)
            if (既定進行 === undefined) {
                throw new Error(`既定のコード進行が見つかりません: ${参照.識別子}`)
            }
            return 既定進行.和音一覧
        }
        case '独自の進行': {
            const 独自進行 = 独自進行一覧.find((進行) => 進行.名前 === 参照.名前)
            if (独自進行 === undefined) {
                throw new Error(`独自のコード進行が見つかりません: ${参照.名前}`)
            }
            return 独自進行.和音一覧
        }
    }
}

// トラックに適用される和音一覧を解決する。打楽器トラックの場合は制約なし(null)を返す。
export function トラックに適用される和音一覧を解決する(
    トラック: トラック定義,
    パターンの進行参照: コード進行参照,
    独自進行一覧: readonly コード進行[],
): readonly 和音[] | null {
    if (トラック.種類 === '打楽器') {
        return null
    }
    const 参照 = トラック.進行の割り当て ?? パターンの進行参照
    return コード進行参照から和音一覧を解決する(参照, 独自進行一覧)
}
