import { パターンのステップ数, type 曲の節, type 楽曲 } from '../../../生成/編集資源契約.ts'
import { 曲全体のステップ数を計算する } from './曲構成の計算.ts'
import { ステップ } from './演奏の時刻/index.ts'

// 再生したときに何が鳴るかの選び。試作は曲構成が空かどうかで暗黙に決まっていたため、人が選べる形へ変える。
export type 演奏の範囲 = 'パターンの繰り返し' | '曲構成のとおり'

export const 演奏の範囲の一覧: readonly 演奏の範囲[] = ['パターンの繰り返し', '曲構成のとおり']

// 楽曲を開いた直後の範囲。演奏の側と操作帯の表示がずれないよう、既定はこの1箇所だけが持つ。
export const 演奏の範囲の既定: 演奏の範囲 = 'パターンの繰り返し'

// 演奏に使う曲構成。パターンだけを繰り返すときと、曲構成が空のときは、どちらも空の曲構成として扱う。
// 曲のステップ位置を解決する は、空の曲構成を「開いているパターンだけの繰り返し」として解く。
export function 演奏に使う曲構成(範囲: 演奏の範囲, 楽曲: 楽曲): readonly 曲の節[] {
    switch (範囲) {
        case 'パターンの繰り返し':
            return []
        case '曲構成のとおり':
            return 楽曲.曲構成
    }
}

// 演奏が1周する長さ。曲構成を使わない(または曲構成が空の)ときはパターン1つ分である。
export function 演奏が1周する長さ(範囲: 演奏の範囲, 楽曲: 楽曲): ステップ {
    const 曲構成 = 演奏に使う曲構成(範囲, 楽曲)
    const 全体のステップ数 = 曲全体のステップ数を計算する(曲構成)
    return ステップ.生成する(全体のステップ数 === 0 ? パターンのステップ数 : 全体のステップ数)
}

export function 演奏の範囲の表示名(範囲: 演奏の範囲): string {
    switch (範囲) {
        case 'パターンの繰り返し':
            return 'いまのパターンを繰り返す'
        case '曲構成のとおり':
            return '曲構成のとおりに鳴らす'
    }
}
