// 見本の曲はどの小節数のパターンへも打ち込む。打楽器・低音・伴奏はステップごとの規則で置くため
// パターンの長さまでそのまま続け、旋律は試作の打ち込みを周期ごとに繰り返してパターンの末尾で切る。

// 打楽器の刻み。試作は8ステップごとにバスドラム、その4つ後ろにスネア、2ステップごとにハイハットを置く。
export function 見本の曲の打楽器のコマンド列(当てどころ: 打ち込みの当てどころ): readonly 楽曲編集コマンド[] {
    const コマンド列: 楽曲編集コマンド[] = []
    for (let ステップ = 0; 当てどころ.パターンの中のステップか(ステップ); ステップ++) {
        const 打点 = (行の位置: number) =>
            当てどころ.音を置くコマンドを作る({ 行の位置, 始まりのステップ: ステップ, 終わりのステップ: ステップ, 進行に従うか: true })
        if (ステップ % 8 === 0) コマンド列.push(打点(見本の曲のバスドラムの行))
        if (ステップ % 8 === 4) コマンド列.push(打点(見本の曲のスネアの行))
        if (ステップ % 2 === 0) コマンド列.push(打点(見本の曲のハイハットの行))
    }
    return コマンド列
}

// 低音。試作は和音1つにつき、その根音を4ステップの区画の先頭で2ステップ伸ばし、3つ目にもう1度置く。
export function 見本の曲の低音のコマンド列(
    当てどころ: 打ち込みの当てどころ,
    音高の行一覧: readonly number[],
    和音一覧: readonly 和音[],
): readonly 楽曲編集コマンド[] {
    const コマンド列: 楽曲編集コマンド[] = []
    for (const { 区画, 和音: 現在の和音 } of 当てどころ.区画ごとの和音一覧(和音一覧)) {
        const 行の位置 = 音高の行一覧.indexOf(現在の和音.根音 + 36)
        if (行の位置 < 0) continue
        const 区画の頭 = 区画 * 4
        コマンド列.push(当てどころ.音を置くコマンドを作る({ 行の位置, 始まりのステップ: 区画の頭, 終わりのステップ: 区画の頭 + 1, 進行に従うか: true }))
        コマンド列.push(当てどころ.音を置くコマンドを作る({ 行の位置, 始まりのステップ: 区画の頭 + 2, 終わりのステップ: 区画の頭 + 2, 進行に従うか: true }))
    }
    return コマンド列
}

// 伴奏。試作は和音が許す音を持つ行を上から順に選び、区画の先頭から1ステップずつずらして置く。
export function 見本の曲の伴奏のコマンド列(
    当てどころ: 打ち込みの当てどころ,
    音高の行一覧: readonly number[],
    和音一覧: readonly 和音[],
): readonly 楽曲編集コマンド[] {
    const コマンド列: 楽曲編集コマンド[] = []
    for (const { 区画, 和音: 現在の和音 } of 当てどころ.区画ごとの和音一覧(和音一覧)) {
        const 許すピッチクラス一覧 = 和音が許す音のピッチクラス一覧(現在の和音)
        const 選ぶ行一覧 = 音高の行一覧
            .map((音高番号, 位置) => ({ 音高番号, 位置 }))
            .filter((行) => 許すピッチクラス一覧.includes(((行.音高番号 % 12) + 12) % 12))
        for (const [順番, 行] of 選ぶ行一覧.entries()) {
            const ステップ = 区画 * 4 + 順番
            if (!当てどころ.パターンの中のステップか(ステップ)) break
            コマンド列.push(
                当てどころ.音を置くコマンドを作る({ 行の位置: 行.位置, 始まりのステップ: ステップ, 終わりのステップ: ステップ, 進行に従うか: true }),
            )
        }
    }
    return コマンド列
}

// 旋律。試作が置く打点を周期ごとに写し、パターンの末尾を越える音は末尾で切る。
// 進行の外へ出る音は、黙って消えないように進行の外の打点として置く。
export function 見本の曲の旋律のコマンド列(
    当てどころ: 打ち込みの当てどころ,
    音高の行一覧: readonly number[],
    和音一覧: readonly 和音[],
): readonly 楽曲編集コマンド[] {
    const コマンド列: 楽曲編集コマンド[] = []
    for (let 周期の頭 = 0; 当てどころ.パターンの中のステップか(周期の頭); 周期の頭 += 見本の曲の旋律の周期のステップ数) {
        for (const [行の位置, 周期内の始まり, 周期内の終わり] of 見本の曲の旋律の打ち込み) {
            const 始まり = 周期の頭 + 周期内の始まり
            if (!当てどころ.パターンの中のステップか(始まり)) continue
            const 音高番号 = 音高の行一覧[行の位置]
            if (音高番号 === undefined) {
                throw new Error(`見本の曲が指す旋律の行がトラックにありません: 行の位置=${行の位置}`)
            }
            const 終わり = 当てどころ.パターンの末尾で切る(周期の頭 + 周期内の終わり)
            const 進行に従うか = 音高番号はその和音で許されるか(音高番号, あるステップの和音を取得する(和音一覧, 始まり))
            コマンド列.push(当てどころ.音を置くコマンドを作る({ 行の位置, 始まりのステップ: 始まり, 終わりのステップ: 終わり, 進行に従うか }))
        }
    }
    return コマンド列
}
