import type { 和音, 楽曲編集コマンド } from '../../../../生成/編集資源契約.ts'
import { あるステップの和音を取得する } from '../音楽理論.ts'

// 打ち込みの当てどころに1つの音を置くときの、行とステップの範囲と進行に従うかの指定。
export interface 音を置く指定 {
    readonly 行の位置: number
    readonly 始まりのステップ: number
    readonly 終わりのステップ: number
    readonly 進行に従うか: boolean
}

export interface 打ち込みの当てどころの生成引数 {
    readonly パターンの名乗り: string
    readonly トラックの位置: number
    readonly パターンのステップ数: number
}

// 見本の曲が音を置く先のパターンとトラックと、そのパターンの長さの組を表す値オブジェクト。
// 4つの打ち込みはどれも「どのパターンのどのトラックへ、どの長さまで置くか」を同じ組で要するため、
// 長さを別の引数にせずこの型が持ち、長さで切る判断もこの型のメソッドに閉じる。
export class 打ち込みの当てどころ {
    private constructor(
        private readonly _パターンの名乗り: string,
        private readonly _トラックの位置: number,
        private readonly _パターンのステップ数: number,
    ) {}

    public static 生成する(引数: 打ち込みの当てどころの生成引数): 打ち込みの当てどころ {
        if (!Number.isInteger(引数.パターンのステップ数) || 引数.パターンのステップ数 <= 0) {
            throw new Error(`パターンのステップ数は1以上の整数でなければなりません: ${引数.パターンのステップ数}`)
        }
        return new 打ち込みの当てどころ(引数.パターンの名乗り, 引数.トラックの位置, 引数.パターンのステップ数)
    }

    public パターンの中のステップか(ステップ: number): boolean {
        return ステップ < this._パターンのステップ数
    }

    // パターンの末尾を越える終わりのステップを末尾のステップへ切り詰める。
    public パターンの末尾で切る(ステップ: number): number {
        return Math.min(ステップ, this._パターンのステップ数 - 1)
    }

    public 音を置くコマンドを作る(指定: 音を置く指定): 楽曲編集コマンド {
        const 対象 = { パターンの名乗り: this._パターンの名乗り, トラックの位置: this._トラックの位置, 行の位置: 指定.行の位置 }
        const { 始まりのステップ, 終わりのステップ, 進行に従うか } = 指定
        if (始まりのステップ === 終わりのステップ) {
            return { 種類: '打点を置く', 値: { 対象, ステップ: 始まりのステップ, 進行に従うか } }
        }
        return { 種類: '音を伸ばす', 値: { 対象, 始まりのステップ, 終わりのステップ, 進行に従うか } }
    }

    // 4ステップを1区画として、パターンの長さぶんの区画の番号と和音の対を順に返す。低音と伴奏が同じ刻みで並ぶため1箇所に置く。
    // 和音は進行を周回させて区画の先頭のステップで決める(演奏と進行の帯の掃除が使う規則と同じ)。
    public 区画ごとの和音一覧(和音一覧: readonly 和音[]): readonly { 区画: number; 和音: 和音 }[] {
        const 対一覧: { 区画: number; 和音: 和音 }[] = []
        for (let 区画 = 0; this.パターンの中のステップか(区画 * 4); 区画++) {
            対一覧.push({ 区画, 和音: あるステップの和音を取得する(和音一覧, 区画 * 4) })
        }
        return 対一覧
    }
}
