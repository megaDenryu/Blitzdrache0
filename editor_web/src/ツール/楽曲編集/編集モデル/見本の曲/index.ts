import type { トラック定義, 楽曲, 楽曲編集コマンド } from '../../../../生成/編集資源契約.ts'
import { コード進行参照から和音一覧を解決する } from '../コード進行参照解決.ts'
import {
    見本の曲のトラックごとの楽器,
    見本の曲の拍毎分,
    見本の曲の進行の参照,
} from './見本の曲の値.ts'
import {
    見本の曲の伴奏のコマンド列,
    見本の曲の低音のコマンド列,
    見本の曲の打楽器のコマンド列,
    見本の曲の旋律のコマンド列,
} from './見本の曲の打ち込み.ts'

export { 見本の曲のトラックごとの楽器, 見本の曲の拍毎分, 見本の曲の進行の参照 } from './見本の曲の値.ts'

// 音高の行を持たないトラックへ旋律や低音を書こうとするのは配線の誤りであるため、明示の失敗にする。
function 音高の行一覧を取り出す(トラック: トラック定義): readonly number[] {
    if (トラック.音の並び.種類 !== '音高の行一覧') {
        throw new Error(`音高の行を持たないトラックです: ${トラック.表示名}`)
    }
    return トラック.音の並び.値
}

function 位置のトラックを取り出す(楽曲: 楽曲, トラックの位置: number): トラック定義 {
    const トラック = 楽曲.トラック構成[トラックの位置]
    if (トラック === undefined) {
        throw new Error(`見本の曲が要求するトラックがありません: トラックの位置=${トラックの位置}`)
    }
    return トラック
}

// 試作の「生楽器アンサンブル デモ」1回ぶんを、楽曲編集コマンドの列として組み立てる。
// 1つの操作として取り消せるように、呼び出し側はこの列をまとめて実行する。
export function 見本の曲のコマンド列を組み立てる(
    楽曲: 楽曲,
    パターンの名乗り: string,
): readonly 楽曲編集コマンド[] {
    const コマンド列: 楽曲編集コマンド[] = [
        { 種類: '拍毎分を変える', 値: { 新しい拍毎分: 見本の曲の拍毎分 } },
        { 種類: 'パターンの進行を変える', 値: { 名乗り: パターンの名乗り, 新しい進行の参照: 見本の曲の進行の参照 } },
        { 種類: 'パターンの打点を全部消す', 値: { パターンの名乗り } },
    ]
    for (const [トラックの位置, 新しい楽器] of 見本の曲のトラックごとの楽器.entries()) {
        コマンド列.push({ 種類: 'トラックの楽器を変える', 値: { トラックの位置, 新しい楽器 } })
        コマンド列.push({
            種類: 'トラックの進行の割り当てを変える',
            値: { トラックの位置, 新しい進行の割り当て: null },
        })
    }

    const 和音一覧 = コード進行参照から和音一覧を解決する(見本の曲の進行の参照, 楽曲.独自進行一覧)
    const 旋律の行一覧 = 音高の行一覧を取り出す(位置のトラックを取り出す(楽曲, 0))
    const 伴奏の行一覧 = 音高の行一覧を取り出す(位置のトラックを取り出す(楽曲, 1))
    const 低音の行一覧 = 音高の行一覧を取り出す(位置のトラックを取り出す(楽曲, 2))
    // 打楽器のトラックは行の位置だけで指すため音高の行は要らないが、実在だけは先に確かめる。
    位置のトラックを取り出す(楽曲, 3)

    コマンド列.push(...見本の曲の打楽器のコマンド列({ パターンの名乗り, トラックの位置: 3 }))
    コマンド列.push(...見本の曲の低音のコマンド列({ パターンの名乗り, トラックの位置: 2 }, 低音の行一覧, 和音一覧))
    コマンド列.push(...見本の曲の伴奏のコマンド列({ パターンの名乗り, トラックの位置: 1 }, 伴奏の行一覧, 和音一覧))
    コマンド列.push(...見本の曲の旋律のコマンド列({ パターンの名乗り, トラックの位置: 0 }, 旋律の行一覧, 和音一覧))
    return コマンド列
}
