import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import type { 表示名の編集をまとめる係 } from '../../文書の表示名の編集/index.ts'
import { 楽曲編集コマンドを適用する } from './操作コマンド/index.ts'
import { 楽曲履歴適用サービス } from './操作コマンド/楽曲履歴適用サービス.ts'
import { タイムラインハンドラ } from './タイムラインハンドラ.ts'
import { 初期楽曲を生成する, 楽曲編集状態 } from './編集モデル/index.ts'
import { 楽曲編集UI状態 } from './楽曲編集UI状態.ts'
import { 楽曲編集の表示の同期 } from './表示の同期.ts'
import type { 楽曲編集画面 } from './画面/index.ts'

// issue #188の例: 曲構成がpattern-1(A)・pattern-b(B)の順に並ぶ楽曲を作り、
// タイムラインハンドラと表示の同期を、操作サービスの同期通知でつないだ本番と同じ配線で組む。
function 移動と取り消しの下ごしらえを作る(): {
    状態: 楽曲編集状態
    UI状態: 楽曲編集UI状態
    操作: 楽曲履歴適用サービス
    タイムライン: タイムラインハンドラ
} {
    const 状態 = new 楽曲編集状態(初期楽曲を生成する('song-188', '揃え直しの確かめ'))
    楽曲編集コマンドを適用する(状態, {
        種類: 'パターンを追加する',
        値: { 名乗り: 'pattern-b', 表示名: 'B', 小節数: 1, 進行の参照: { 種類: '既定の進行', 識別子: '戦闘と道' } },
    })
    楽曲編集コマンドを適用する(状態, { 種類: 'パターンの小節数を変える', 値: { 名乗り: 'pattern-1', 新しい小節数: 1 } })
    楽曲編集コマンドを適用する(状態, { 種類: '曲の節を追加する', 値: { パターンの名乗り: 'pattern-1', 繰り返し回数: 1 } })
    楽曲編集コマンドを適用する(状態, { 種類: '曲の節を追加する', 値: { パターンの名乗り: 'pattern-b', 繰り返し回数: 1 } })

    const UI状態 = new 楽曲編集UI状態()
    const 画面 = { 表示を更新する: () => {} } as unknown as 楽曲編集画面
    const 表示名の編集 = { 正本の表示名に合わせる: () => {} } as unknown as 表示名の編集をまとめる係
    const 同期 = new 楽曲編集の表示の同期(画面, 状態, UI状態, 表示名の編集)
    const 表示を再構築する = (): void => { 同期.再構築する() }
    const 操作 = new 楽曲履歴適用サービス(状態, 表示を再構築する)
    const タイムライン = new タイムラインハンドラ(状態, UI状態, 操作, 表示を再構築する)

    return { 状態, UI状態, 操作, タイムライン }
}

describe('取り消しの後の選択とパターンの揃え直し(issue #188)', () => {
    it('Bのカードを前へ移動してから取り消すと、選択中のカードの位置と格子が映すパターンが食い違わない', () => {
        const { 状態, UI状態, 操作, タイムライン } = 移動と取り消しの下ごしらえを作る()

        // BのカードをA(節の位置0)の前へ移動する。issue #88の追従により選択はBへ付いてくる。
        タイムライン.on枠操作({ 節の位置: 1, 繰り返しの何回目: 0, 小節の番号: 0 }, '前へ移動')
        assert.deepEqual(UI状態.選択中のカード, { 節の位置: 0, 繰り返しの何回目: 0, 小節の番号: 0 })
        assert.equal(状態.選択中パターンの名乗り, 'pattern-b')

        操作.直前の操作を取り消す()

        // 曲構成はA・Bの順へ戻る。選択中のカードの位置は変えない(取り消した操作の前の選択へは
        // 戻さない、判断15)ため位置0のままだが、位置0が指す先は取り消しでAへ戻っているので、
        // 格子が映す選択中パターンもAへ揃う(強調はAなのに格子はBのまま、という食い違いを防ぐ)。
        assert.deepEqual(UI状態.選択中のカード, { 節の位置: 0, 繰り返しの何回目: 0, 小節の番号: 0 })
        assert.equal(状態.選択中パターンの名乗り, 'pattern-1')
        assert.equal(状態.楽曲.曲構成[0]?.パターンの名乗り, 'pattern-1')
        assert.equal(状態.楽曲.曲構成[1]?.パターンの名乗り, 'pattern-b')
    })
})
