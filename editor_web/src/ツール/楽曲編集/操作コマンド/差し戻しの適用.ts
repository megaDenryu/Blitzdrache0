import type { 楽曲編集状態 } from '../編集モデル/index.ts'
import type { 差し戻し断片 } from './差し戻し断片.ts'
import { 打ち込み差し戻しを適用する } from './打ち込み差し戻し適用.ts'
import { 楽曲属性差し戻しを適用する } from './楽曲属性差し戻し適用.ts'
import { パターン差し戻しを適用する } from './パターン差し戻し適用.ts'
import { コード進行と曲構成差し戻しを適用する } from './コード進行と曲構成差し戻し適用.ts'

// 差し戻し断片の情報に基づき、編集状態を変更前の値へ復元する。
export function 差し戻しを適用する(状態: 楽曲編集状態, 断片: 差し戻し断片): void {
    switch (断片.種類) {
        case '打点を置く':
        case '打点を消す':
        case '音を伸ばす':
        case '範囲の打点を消す':
        case 'パターンの打点を全部消す':
            return 打ち込み差し戻しを適用する(状態, 断片)
        case 'テンポを変える':
        case 'ミキサー設定を変える':
        case '楽曲の表示名を変える':
        case 'トラックの楽器を変える':
        case 'トラックの音量を変える':
        case 'トラックの進行の割り当てを変える':
            return 楽曲属性差し戻しを適用する(状態, 断片)
        case 'パターンを追加する':
        case 'パターンを削除する':
        case 'パターンの進行を変える':
        case 'パターンの表示名を変える':
            return パターン差し戻しを適用する(状態, 断片)
        case '独自の進行を保存する':
        case '独自の進行を削除する':
        case '曲の節を追加する':
        case '曲の節を変える':
        case '曲の節を削除する':
        case '曲の節を並べ替える':
            return コード進行と曲構成差し戻しを適用する(状態, 断片)
        case 'まとめた操作': {
            // まとめた操作は積んだ順の逆から戻す。同じ升目を2度触ったときに最初の値へ帰るためである。
            for (let 位置 = 断片.内訳.length - 1; 位置 >= 0; 位置--) {
                const 内側の断片 = 断片.内訳[位置]
                if (内側の断片 !== undefined) 差し戻しを適用する(状態, 内側の断片)
            }
            return
        }
    }
    const 網羅性検査: never = 断片
    throw new Error(`未対応の差し戻し断片種類: ${JSON.stringify(網羅性検査)}`)
}
