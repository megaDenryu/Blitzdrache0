import type { 楽曲編集状態 } from '../編集モデル/index.ts'
import type { 打ち込み差し戻し断片 } from './差し戻し断片/打ち込み差し戻し.ts'

export function 打ち込み差し戻しを適用する(
    状態: 楽曲編集状態,
    断片: 打ち込み差し戻し断片,
): void {
    switch (断片.種類) {
        case '打点を置く':
        case '打点を消す': {
            const 行 = 状態.打ち込み先の行を取得する(断片.対象)
            行.ステップのセルの数値を書き換える(断片.ステップ, 断片.変更前値)
            return
        }
        case '音を伸ばす':
        case '範囲の打点を消す': {
            const 行 = 状態.打ち込み先の行を取得する(断片.対象)
            for (const [位置, 値] of 断片.変更前値一覧.entries()) {
                行.ステップのセルの数値を書き換える(断片.始まりのステップ + 位置, 値)
            }
            return
        }
        case 'パターンの打点を全部消す': {
            const パターン = 状態.パターンを取得する(断片.パターンの名乗り)
            パターン.格子 = 断片.変更前格子.map((tg) => ({
                行一覧: tg.行一覧.map((r) => [...r]),
            }))
            return
        }
    }
    const 網羅性検査: never = 断片
    throw new Error(`未対応の打ち込み差し戻し断片種類: ${JSON.stringify(網羅性検査)}`)
}
