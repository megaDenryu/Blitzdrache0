import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { 楽曲編集コマンド } from '../../../生成/編集資源契約.ts'
import { 楽曲編集状態 } from '../編集モデル/index.ts'
import { 楽曲編集コマンドを適用する, 差し戻しを適用する } from './index.ts'

function 小節数を指定してパターンを追加した状態を作る(小節数: number): 楽曲編集状態 {
    const 状態 = new 楽曲編集状態()
    楽曲編集コマンドを適用する(状態, {
        種類: 'パターンを追加する',
        値: {
            名乗り: 'bar-pattern',
            表示名: '小節数試験',
            小節数,
            進行の参照: { 種類: '既定の進行', 識別子: '王道進行' },
        },
    })
    return 状態
}

describe('パターンの小節数を変えるコマンドの適用と差し戻しテスト', () => {
    it('小節数2を4へ増やすと格子が64列になり、差し戻すと32列へ戻る', () => {
        const 状態 = 小節数を指定してパターンを追加した状態を作る(2)
        const 元状態 = new 楽曲編集状態(状態.楽曲を取得する())
        const コマンド: 楽曲編集コマンド = {
            種類: 'パターンの小節数を変える',
            値: { 名乗り: 'bar-pattern', 新しい小節数: 4 },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        const 増やした後 = 状態.パターンを取得する('bar-pattern')
        assert.equal(増やした後.小節数, 4)
        assert.equal(増やした後.格子[0]?.行一覧[0]?.length, 64)
        差し戻しを適用する(状態, 断片)
        assert.deepEqual(状態.楽曲, 元状態.楽曲)
    })

    it('小節数4を1へ減らして戻すと、消えた末尾の打点が復元される', () => {
        const 状態 = 小節数を指定してパターンを追加した状態を作る(4)
        楽曲編集コマンドを適用する(状態, {
            種類: '打点を置く',
            値: {
                対象: { パターンの名乗り: 'bar-pattern', トラックの位置: 0, 行の位置: 0 },
                ステップ: 60,
                進行に従うか: true,
            },
        })
        const 元状態 = new 楽曲編集状態(状態.楽曲を取得する())
        const 断片 = 楽曲編集コマンドを適用する(状態, {
            種類: 'パターンの小節数を変える',
            値: { 名乗り: 'bar-pattern', 新しい小節数: 1 },
        })
        const 減らした後 = 状態.パターンを取得する('bar-pattern')
        assert.equal(減らした後.小節数, 1)
        assert.equal(減らした後.格子[0]?.行一覧[0]?.length, 16)
        差し戻しを適用する(状態, 断片)
        assert.deepEqual(状態.楽曲, 元状態.楽曲)
        assert.equal(状態.パターンを取得する('bar-pattern').格子[0]?.行一覧[0]?.[60], 1)
    })
})
