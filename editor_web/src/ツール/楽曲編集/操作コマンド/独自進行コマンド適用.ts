import type {
    コード進行,
    独自の進行を削除する,
    独自の進行を保存する,
} from '../../../生成/編集資源契約.ts'
import type { 楽曲編集状態 } from '../編集モデル/index.ts'
import type {
    独自の進行を削除する差し戻し,
    独自の進行を保存する差し戻し,
} from './差し戻し断片.ts'

export function 独自の進行を保存するコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 独自の進行を保存する,
): 独自の進行を保存する差し戻し {
    const 既存位置 = 状態.楽曲.独自進行一覧.findIndex((p) => p.名前 === コマンド.進行.名前)
    const 新進行: コード進行 = {
        名前: コマンド.進行.名前,
        和音一覧: コマンド.進行.和音一覧.map((和音) => ({ ...和音 })),
    }
    if (既存位置 !== -1) {
        const 既存 = 状態.楽曲.独自進行一覧[既存位置]
        if (既存 === undefined) {
            throw new Error(`既存進行の取得に失敗しました`)
        }
        const 変更前進行: コード進行 = {
            名前: 既存.名前,
            和音一覧: 既存.和音一覧.map((和音) => ({ ...和音 })),
        }
        状態.楽曲.独自進行一覧[既存位置] = 新進行
        return {
            種類: '独自の進行を保存する',
            進行名: コマンド.進行.名前,
            変更前進行,
            元の位置: 既存位置,
        }
    }
    状態.楽曲.独自進行一覧.push(新進行)
    return {
        種類: '独自の進行を保存する',
        進行名: コマンド.進行.名前,
        変更前進行: null,
        元の位置: null,
    }
}

export function 独自の進行を削除するコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 独自の進行を削除する,
): 独自の進行を削除する差し戻し {
    const 元の位置 = 状態.楽曲.独自進行一覧.findIndex((p) => p.名前 === コマンド.名前)
    if (元の位置 === -1) {
        throw new Error(`削除対象の独自進行が見つかりません: ${コマンド.名前}`)
    }
    const 削除対象 = 状態.楽曲.独自進行一覧[元の位置]
    if (削除対象 === undefined) {
        throw new Error(`削除対象の独自進行が取得できません`)
    }
    const 削除された進行: コード進行 = {
        名前: 削除対象.名前,
        和音一覧: 削除対象.和音一覧.map((和音) => ({ ...和音 })),
    }
    状態.楽曲.独自進行一覧.splice(元の位置, 1)
    return {
        種類: '独自の進行を削除する',
        削除された進行,
        元の位置,
    }
}
