import type { 差し戻し断片 } from './差し戻し断片.ts'
import { 打点を消すコマンドを適用する, 打点を置くコマンドを適用する } from './単一打点コマンド適用.ts'
import {
    パターンの打点を全部消すコマンドを適用する,
    範囲の打点を消すコマンドを適用する,
    音を伸ばすコマンドを適用する,
} from './範囲打点コマンド適用.ts'
import {
    トラックの楽器を変えるコマンドを適用する,
    トラックの進行の割り当てを変えるコマンドを適用する,
    トラックの音量を変えるコマンドを適用する,
    ミキサー設定を変えるコマンドを適用する,
    テンポを変えるコマンドを適用する,
    楽曲の表示名を変えるコマンドを適用する,
} from './楽曲属性コマンド適用.ts'
import {
    パターンを追加するコマンドを適用する,
    パターンを削除するコマンドを適用する,
} from './パターン追加削除コマンド適用.ts'
import {
    パターンの進行を変えるコマンドを適用する,
    パターンの表示名を変えるコマンドを適用する,
} from './パターン変更コマンド適用.ts'
import {
    独自の進行を削除するコマンドを適用する,
    独自の進行を保存するコマンドを適用する,
} from './独自進行コマンド適用.ts'
import {
    曲の節を削除するコマンドを適用する,
    曲の節を追加するコマンドを適用する,
    曲の節を変えるコマンドを適用する,
    曲の節を並べ替えるコマンドを適用する,
} from './曲構成コマンド適用.ts'

// 楽曲編集コマンドを編集状態へ適用し、差し戻し断片を返す。
export function 楽曲編集コマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 楽曲編集コマンド,
): 差し戻し断片 {
    switch (コマンド.種類) {
        case '打点を置く':
            return 打点を置くコマンドを適用する(状態, コマンド.値)
        case '打点を消す':
            return 打点を消すコマンドを適用する(状態, コマンド.値)
        case '音を伸ばす':
            return 音を伸ばすコマンドを適用する(状態, コマンド.値)
        case '範囲の打点を消す':
            return 範囲の打点を消すコマンドを適用する(状態, コマンド.値)
        case 'パターンの打点を全部消す':
            return パターンの打点を全部消すコマンドを適用する(状態, コマンド.値)
        case 'テンポを変える':
            return テンポを変えるコマンドを適用する(状態, コマンド.値)
        case 'ミキサー設定を変える':
            return ミキサー設定を変えるコマンドを適用する(状態, コマンド.値)
        case '楽曲の表示名を変える':
            return 楽曲の表示名を変えるコマンドを適用する(状態, コマンド.値)
        case 'トラックの楽器を変える':
            return トラックの楽器を変えるコマンドを適用する(状態, コマンド.値)
        case 'トラックの音量を変える':
            return トラックの音量を変えるコマンドを適用する(状態, コマンド.値)
        case 'トラックの進行の割り当てを変える':
            return トラックの進行の割り当てを変えるコマンドを適用する(状態, コマンド.値)
        case 'パターンを追加する':
            return パターンを追加するコマンドを適用する(状態, コマンド.値)
        case 'パターンを削除する':
            return パターンを削除するコマンドを適用する(状態, コマンド.値)
        case 'パターンの進行を変える':
            return パターンの進行を変えるコマンドを適用する(状態, コマンド.値)
        case 'パターンの表示名を変える':
            return パターンの表示名を変えるコマンドを適用する(状態, コマンド.値)
        case '独自の進行を保存する':
            return 独自の進行を保存するコマンドを適用する(状態, コマンド.値)
        case '独自の進行を削除する':
            return 独自の進行を削除するコマンドを適用する(状態, コマンド.値)
        case '曲の節を追加する':
            return 曲の節を追加するコマンドを適用する(状態, コマンド.値)
        case '曲の節を変える':
            return 曲の節を変えるコマンドを適用する(状態, コマンド.値)
        case '曲の節を削除する':
            return 曲の節を削除するコマンドを適用する(状態, コマンド.値)
        case '曲の節を並べ替える':
            return 曲の節を並べ替えるコマンドを適用する(状態, コマンド.値)
    }
    const 網羅性検査: never = コマンド
    throw new Error(`未対応の楽曲編集コマンド種類: ${JSON.stringify(網羅性検査)}`)
}
