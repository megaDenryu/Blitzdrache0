import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 小節あたりのステップ数, type 楽曲編集コマンド } from '../../../生成/編集資源契約.ts'
import {
    パターン格子を進行に合わせて掃除する,
    初期楽曲を生成する,
    楽曲編集状態,
    見本の曲のコマンド列を組み立てる,
} from '../編集モデル/index.ts'
import { 楽曲編集コマンドを適用する } from './編集コマンドの適用.ts'
import { 楽曲履歴適用サービス } from './楽曲履歴適用サービス.ts'

function 小節数を変えた状態を作る(小節数: number): 楽曲編集状態 {
    const 状態 = new 楽曲編集状態(初期楽曲を生成する('song-1', '見本の曲'))
    楽曲編集コマンドを適用する(状態, { 種類: 'パターンの小節数を変える', 値: { 名乗り: 'pattern-1', 新しい小節数: 小節数 } })
    return 状態
}

// 打ち込みのコマンドが指すステップの最大値。打ち込み以外のコマンドは対象外として -1 を返す。
function 指す最後のステップを求める(コマンド: 楽曲編集コマンド): number {
    if (コマンド.種類 === '打点を置く') return コマンド.値.ステップ
    if (コマンド.種類 === '音を伸ばす') return コマンド.値.終わりのステップ
    return -1
}

describe('見本の曲をパターンの小節数へ合わせる', () => {
    for (const 小節数 of [1, 2, 3]) {
        it(`小節数${小節数}のパターンへ、格子の外を指すコマンドを出さずに入り、掃除で1つも消えない`, () => {
            const 状態 = 小節数を変えた状態を作る(小節数)
            const コマンド列 = 見本の曲のコマンド列を組み立てる(状態.楽曲を取得する(), 'pattern-1')
            const 最後のステップ = Math.max(...コマンド列.map(指す最後のステップを求める))
            assert.ok(最後のステップ >= 0 && 最後のステップ < 小節数 * 小節あたりのステップ数, `最後のステップ=${最後のステップ}`)

            const 操作 = new 楽曲履歴適用サービス(状態)
            操作.コマンド列を1つの操作として実行する(コマンド列)
            const 楽曲 = 状態.楽曲を取得する()
            const パターン = 楽曲.パターン一覧[0]
            const 掃除後 = パターン格子を進行に合わせて掃除する(パターン, 楽曲.トラック構成, パターン.進行の参照, 楽曲.独自進行一覧)
            assert.deepEqual(掃除後, パターン.格子)
        })
    }

    it('小節数3のパターンでは、3小節目にも旋律の打点が入る', () => {
        const 状態 = 小節数を変えた状態を作る(3)
        const コマンド列 = 見本の曲のコマンド列を組み立てる(状態.楽曲を取得する(), 'pattern-1')
        const 旋律の始まり一覧 = コマンド列.flatMap((コマンド) => {
            if (コマンド.種類 === '打点を置く' && コマンド.値.対象.トラックの位置 === 0) return [コマンド.値.ステップ]
            if (コマンド.種類 === '音を伸ばす' && コマンド.値.対象.トラックの位置 === 0) return [コマンド.値.始まりのステップ]
            return []
        })
        assert.ok(旋律の始まり一覧.some((ステップ) => ステップ >= 32), `旋律の始まり=${旋律の始まり一覧.join(',')}`)
    })
})

describe('コマンド列を1つの操作として実行するの途中の失敗', () => {
    it('途中のコマンドが格子の外を指して失敗したら、状態を実行前へ戻し、履歴に積まない', () => {
        const 状態 = 小節数を変えた状態を作る(1)
        const 実行前 = structuredClone(状態.楽曲を取得する())
        const 操作 = new 楽曲履歴適用サービス(状態)
        const 対象 = { パターンの名乗り: 'pattern-1', トラックの位置: 3, 行の位置: 0 }
        assert.throws(() =>
            操作.コマンド列を1つの操作として実行する([
                { 種類: 'テンポを変える', 値: { 新しいテンポ: 90 } },
                { 種類: '打点を置く', 値: { 対象, ステップ: 0, 進行に従うか: true } },
                { 種類: '打点を置く', 値: { 対象, ステップ: 小節あたりのステップ数, 進行に従うか: true } },
            ]),
        )
        assert.deepEqual(状態.楽曲を取得する(), 実行前)
        assert.equal(操作.履歴件数, 0)
    })
})
