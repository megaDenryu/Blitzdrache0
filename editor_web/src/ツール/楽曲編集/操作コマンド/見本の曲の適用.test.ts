import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { テンポの上限, テンポの下限, 小節あたりのステップ数 } from '../../../生成/編集資源契約.ts'
import {
    パターン格子を進行に合わせて掃除する,
    初期楽曲を生成する,
    楽曲編集状態,
    見本の曲のコマンド列を組み立てる,
    見本の曲のトラックごとの楽器,
    見本の曲のテンポ,
    見本の曲の進行の参照,
    パターンのステップで鳴り始める音一覧を求める,
} from '../編集モデル/index.ts'
import { 楽曲編集コマンドを適用する } from './編集コマンドの適用.ts'
import { 差し戻しを適用する } from './差し戻しの適用.ts'
import type { 差し戻し断片 } from './差し戻し断片.ts'

function 見本を入れた状態を作る(): 楽曲編集状態 {
    const 状態 = new 楽曲編集状態(初期楽曲を生成する('song-1', '見本の曲'))
    const コマンド列 = 見本の曲のコマンド列を組み立てる(状態.楽曲を取得する(), 'pattern-1')
    for (const コマンド of コマンド列) 楽曲編集コマンドを適用する(状態, コマンド)
    return 状態
}

describe('見本の曲', () => {
    it('テンポ・進行・楽器が試作の値のとおりに入ること', () => {
        const 楽曲 = 見本を入れた状態を作る().楽曲を取得する()
        assert.strictEqual(楽曲.テンポ, 見本の曲のテンポ)
        assert.ok(楽曲.テンポ >= テンポの下限 && 楽曲.テンポ <= テンポの上限)
        assert.deepEqual(楽曲.パターン一覧[0].進行の参照, 見本の曲の進行の参照)
        assert.deepEqual(
            楽曲.トラック構成.map((トラック) => トラック.楽器),
            見本の曲のトラックごとの楽器,
        )
    })

    it('格子のセルが契約の0から4の値だけで、行の数がトラックの音の並びと揃うこと', () => {
        const 楽曲 = 見本を入れた状態を作る().楽曲を取得する()
        const パターン = 楽曲.パターン一覧[0]
        assert.strictEqual(パターン.格子.length, 楽曲.トラック構成.length)
        for (const [位置, トラック格子] of パターン.格子.entries()) {
            assert.strictEqual(トラック格子.行一覧.length, 楽曲.トラック構成[位置].音の並び.値.length)
            for (const 行 of トラック格子.行一覧) {
                assert.strictEqual(行.length, パターン.小節数 * 小節あたりのステップ数)
                for (const セル値 of 行) {
                    assert.ok(Number.isInteger(セル値) && セル値 >= 0 && セル値 <= 4, `セル値=${セル値}`)
                }
            }
        }
    })

    // 道具が作る初期値が道具自身の検証を通ることを機械で確かめる(エディター制作スキル第2条)。
    it('見本の打ち込みが、進行に合わせた掃除で1つも消えないこと', () => {
        const 楽曲 = 見本を入れた状態を作る().楽曲を取得する()
        const パターン = 楽曲.パターン一覧[0]
        const 掃除後 = パターン格子を進行に合わせて掃除する(
            パターン,
            楽曲.トラック構成,
            パターン.進行の参照,
            楽曲.独自進行一覧,
        )
        assert.deepEqual(掃除後, パターン.格子)
    })

    it('4本すべてのトラックに音が入り、パターンの先頭で複数の音が鳴り始めること', () => {
        const 楽曲 = 見本を入れた状態を作る().楽曲を取得する()
        const パターン = 楽曲.パターン一覧[0]
        for (const [位置, トラック格子] of パターン.格子.entries()) {
            const 打点の数 = トラック格子.行一覧.reduce(
                (合計, 行) => 合計 + 行.filter((セル値) => セル値 === 1 || セル値 === 3).length,
                0,
            )
            assert.ok(打点の数 > 0, `トラック${位置}に音が無い`)
        }
        const 先頭の音一覧 = パターンのステップで鳴り始める音一覧を求める(楽曲, パターン, 0)
        assert.ok(先頭の音一覧.length >= 3, `先頭で鳴る音=${先頭の音一覧.length}`)
    })

    it('まとめた差し戻しで、見本を入れる前の格子へ1度で戻ること', () => {
        const 状態 = new 楽曲編集状態(初期楽曲を生成する('song-1', '見本の曲'))
        const 入れる前 = 状態.楽曲を取得する()
        const 内訳: 差し戻し断片[] = []
        for (const コマンド of 見本の曲のコマンド列を組み立てる(入れる前, 'pattern-1')) {
            内訳.push(楽曲編集コマンドを適用する(状態, コマンド))
        }
        assert.notDeepEqual(状態.楽曲を取得する(), 入れる前)
        差し戻しを適用する(状態, { 種類: 'まとめた操作', 内訳 })
        assert.deepEqual(状態.楽曲を取得する(), 入れる前)
    })
})
