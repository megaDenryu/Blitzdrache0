import type { 楽曲編集状態 } from '../編集モデル/index.ts'
import type { パターン差し戻し断片 } from './差し戻し断片/パターン差し戻し.ts'

export function パターン差し戻しを適用する(
    状態: 楽曲編集状態,
    断片: パターン差し戻し断片,
): void {
    switch (断片.種類) {
        case 'パターンを追加する':
            状態.楽曲.パターン一覧 = 状態.楽曲.パターン一覧.filter((p) => p.名乗り !== 断片.名乗り)
            状態.選択中パターンが失われていたら選び直す()
            return
        case 'パターンを削除する': {
            状態.楽曲.パターン一覧.splice(断片.元の位置, 0, {
                名乗り: 断片.削除されたパターン.名乗り,
                表示名: 断片.削除されたパターン.表示名,
                進行の参照: { ...断片.削除されたパターン.進行の参照 },
                格子: 断片.削除されたパターン.格子.map((tg) => ({
                    行一覧: tg.行一覧.map((r) => [...r]),
                })),
            })
            for (const 記録 of 断片.連動して削除された節一覧) {
                状態.楽曲.曲構成.splice(記録.節の位置, 0, { ...記録.節 })
            }
            return
        }
        case 'パターンの進行を変える': {
            const パターン = 状態.パターンを取得する(断片.名乗り)
            パターン.進行の参照 = { ...断片.変更前進行の参照 }
            パターン.格子 = 断片.変更前格子.map((tg) => ({
                行一覧: tg.行一覧.map((r) => [...r]),
            }))
            return
        }
        case 'パターンの表示名を変える': {
            const パターン = 状態.パターンを取得する(断片.名乗り)
            パターン.表示名 = 断片.変更前表示名
            return
        }
    }
    const 網羅性検査: never = 断片
    throw new Error(`未対応のパターン差し戻し断片種類: ${JSON.stringify(網羅性検査)}`)
}
