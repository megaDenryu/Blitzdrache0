import {
    曲の節の繰り返し回数の下限,
    type 曲の節を削除する,
    type 曲の節を追加する,
    type 曲の節を変える,
    type 曲の節を並べ替える,
} from '../../../生成/編集資源契約.ts'
import type { 楽曲編集状態 } from '../編集モデル/index.ts'
import type {
    曲の節を削除する差し戻し,
    曲の節を追加する差し戻し,
    曲の節を変える差し戻し,
    曲の節を並べ替える差し戻し,
} from './差し戻し断片.ts'

export function 曲の節を追加するコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 曲の節を追加する,
): 曲の節を追加する差し戻し {
    if (!状態.パターンが存在するか(コマンド.パターンの名乗り)) {
        throw new Error(`指定されたパターンが存在しません: ${コマンド.パターンの名乗り}`)
    }
    状態.楽曲.曲構成.push({
        パターンの名乗り: コマンド.パターンの名乗り,
        繰り返し回数: Math.max(曲の節の繰り返し回数の下限, コマンド.繰り返し回数),
    })
    return {
        種類: '曲の節を追加する',
        節の位置: 状態.楽曲.曲構成.length - 1,
    }
}

export function 曲の節を変えるコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 曲の節を変える,
): 曲の節を変える差し戻し {
    const 節 = 状態.楽曲.曲構成[コマンド.節の位置]
    if (節 === undefined) {
        throw new Error(`指定位置の曲の節が存在しません: ${コマンド.節の位置}`)
    }
    if (!状態.パターンが存在するか(コマンド.新しいパターンの名乗り)) {
        throw new Error(`指定されたパターンが存在しません: ${コマンド.新しいパターンの名乗り}`)
    }
    const 変更前節 = { ...節 }
    状態.楽曲.曲構成[コマンド.節の位置] = {
        パターンの名乗り: コマンド.新しいパターンの名乗り,
        繰り返し回数: Math.max(曲の節の繰り返し回数の下限, コマンド.新しい繰り返し回数),
    }
    return {
        種類: '曲の節を変える',
        節の位置: コマンド.節の位置,
        変更前節,
    }
}

export function 曲の節を削除するコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 曲の節を削除する,
): 曲の節を削除する差し戻し {
    const 節 = 状態.楽曲.曲構成[コマンド.節の位置]
    if (節 === undefined) {
        throw new Error(`指定位置の曲の節が存在しません: ${コマンド.節の位置}`)
    }
    const 削除された節 = { ...節 }
    状態.楽曲.曲構成.splice(コマンド.節の位置, 1)
    return {
        種類: '曲の節を削除する',
        節の位置: コマンド.節の位置,
        削除された節,
    }
}

export function 曲の節を並べ替えるコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 曲の節を並べ替える,
): 曲の節を並べ替える差し戻し {
    const 節数 = 状態.楽曲.曲構成.length
    if (コマンド.元の位置 < 0 || コマンド.元の位置 >= 節数) {
        throw new Error(`元の位置が範囲外です: ${コマンド.元の位置}`)
    }
    if (コマンド.先の位置 < 0 || コマンド.先の位置 >= 節数) {
        throw new Error(`先の位置が範囲外です: ${コマンド.先の位置}`)
    }
    const [節] = 状態.楽曲.曲構成.splice(コマンド.元の位置, 1)
    if (節 === undefined) {
        throw new Error(`曲の節の取り出しに失敗しました`)
    }
    状態.楽曲.曲構成.splice(コマンド.先の位置, 0, 節)
    return {
        種類: '曲の節を並べ替える',
        元の位置: コマンド.元の位置,
        先の位置: コマンド.先の位置,
    }
}
