import {
    type パターン,
    type パターンを追加する,
    type パターンを削除する,
} from '../../../生成/編集資源契約.ts'
import {
    トラック構成から空の格子一覧を生成する,
    type 楽曲編集状態,
} from '../編集モデル/index.ts'
import type {
    削除された曲の節の記録,
    パターンを追加する差し戻し,
    パターンを削除する差し戻し,
} from './差し戻し断片.ts'

export function パターンを追加するコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: パターンを追加する,
): パターンを追加する差し戻し {
    if (状態.パターンが存在するか(コマンド.名乗り)) {
        throw new Error(`同名乗りのパターンが既に存在します: ${コマンド.名乗り}`)
    }
    const 格子 = トラック構成から空の格子一覧を生成する(状態.楽曲.トラック構成, コマンド.小節数)
    const 新パターン: パターン = {
        名乗り: コマンド.名乗り,
        表示名: コマンド.表示名,
        小節数: コマンド.小節数,
        進行の参照: { ...コマンド.進行の参照 },
        格子,
    }
    状態.楽曲.パターン一覧.push(新パターン)
    return { 種類: 'パターンを追加する', 名乗り: コマンド.名乗り }
}

export function パターンを削除するコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: パターンを削除する,
): パターンを削除する差し戻し {
    const 元の位置 = 状態.楽曲.パターン一覧.findIndex((p) => p.名乗り === コマンド.名乗り)
    if (元の位置 === -1) {
        throw new Error(`削除対象のパターンが見つかりません: ${コマンド.名乗り}`)
    }
    if (状態.楽曲.パターン一覧.length <= 1) {
        throw new Error(`楽曲には最低1つのパターンが必要です`)
    }
    const 削除されたパターン = 状態.楽曲.パターン一覧[元の位置]
    if (削除されたパターン === undefined) {
        throw new Error(`削除対象のパターンが取得できません`)
    }
    const 削除パターンの写し: パターン = {
        名乗り: 削除されたパターン.名乗り,
        表示名: 削除されたパターン.表示名,
        小節数: 削除されたパターン.小節数,
        進行の参照: { ...削除されたパターン.進行の参照 },
        格子: 削除されたパターン.格子.map((tg) => ({
            行一覧: tg.行一覧.map((row) => [...row]),
        })),
    }
    const 連動して削除された節一覧: 削除された曲の節の記録[] = []
    for (let i = 0; i < 状態.楽曲.曲構成.length; i++) {
        const 節 = 状態.楽曲.曲構成[i]
        if (節 && 節.パターンの名乗り === コマンド.名乗り) {
            連動して削除された節一覧.push({ 節の位置: i, 節: { ...節 } })
        }
    }
    状態.楽曲.曲構成 = 状態.楽曲.曲構成.filter((節) => 節.パターンの名乗り !== コマンド.名乗り)
    状態.楽曲.パターン一覧.splice(元の位置, 1)
    状態.選択中パターンが失われていたら選び直す()
    return {
        種類: 'パターンを削除する',
        削除されたパターン: 削除パターンの写し,
        元の位置,
        連動して削除された節一覧,
    }
}
