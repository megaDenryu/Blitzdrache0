import { 小節あたりのステップ数, type パターンの小節数を変える } from '../../../生成/編集資源契約.ts'
import type { 楽曲編集状態 } from '../編集モデル/index.ts'
import type { パターンの小節数を変える差し戻し, 切り落とされたトラック格子 } from './差し戻し断片.ts'

export function パターンの小節数を変えるコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: パターンの小節数を変える,
): パターンの小節数を変える差し戻し {
    const 対象パターン = 状態.パターンを取得する(コマンド.名乗り)
    const 変更前の小節数 = 対象パターン.小節数
    const 新しいステップ数 = コマンド.新しい小節数 * 小節あたりのステップ数
    const 切り落とした末尾のセル: 切り落とされたトラック格子[] = 対象パターン.格子.map((トラック格子) => ({
        行一覧: トラック格子.行一覧.map((行) => (行.length > 新しいステップ数 ? 行.slice(新しいステップ数) : [])),
    }))
    for (const トラック格子 of 対象パターン.格子) {
        for (const 行 of トラック格子.行一覧) {
            if (行.length > 新しいステップ数) {
                行.length = 新しいステップ数
            } else {
                while (行.length < 新しいステップ数) 行.push(0)
            }
        }
    }
    対象パターン.小節数 = コマンド.新しい小節数
    return {
        種類: 'パターンの小節数を変える',
        名乗り: コマンド.名乗り,
        変更前の小節数,
        切り落とした末尾のセル,
    }
}
