import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { 曲の節 } from '../../../生成/編集資源契約.ts'
import { カードの操作をコマンドへ写す } from './カードの操作をコマンドへ写す.ts'

describe('カードの操作をコマンドへ写すテスト(末尾へ追加・削除・複製)', () => {
    const 曲構成: readonly 曲の節[] = [
        { パターンの名乗り: 'a', 繰り返し回数: 2 },
        { パターンの名乗り: 'b', 繰り返し回数: 1 },
        { パターンの名乗り: 'c', 繰り返し回数: 8 },
    ]

    it('末尾へ追加は曲の節を追加するへ写し、選択を足した節の先頭のカード(小節の番号0)へ移す', () => {
        const 写し = カードの操作をコマンドへ写す(曲構成, { 種類: '末尾へ追加', パターンの名乗り: 'a' })
        assert.deepEqual(写し, {
            種類: '積む',
            コマンド: { 種類: '曲の節を追加する', 値: { パターンの名乗り: 'a', 繰り返し回数: 1 } },
            操作の後の選択: { 節の位置: 3, 繰り返しの何回目: 0, 小節の番号: 0 },
        })
    })

    it('削除は繰り返し回数が2以上なら曲の節を変えるで1減らし、選択を外す', () => {
        const 位置 = { 節の位置: 0, 繰り返しの何回目: 0, 小節の番号: 1 }
        const 写し = カードの操作をコマンドへ写す(曲構成, { 種類: '削除', 位置 })
        assert.deepEqual(写し, { 種類: '積む', コマンド: { 種類: '曲の節を変える', 値: { 節の位置: 0, 新しいパターンの名乗り: 'a', 新しい繰り返し回数: 1 } }, 操作の後の選択: null })
    })

    it('削除は繰り返し回数が1なら曲の節を削除するへ写し、選択を外す', () => {
        const 位置 = { 節の位置: 1, 繰り返しの何回目: 0, 小節の番号: 0 }
        const 写し = カードの操作をコマンドへ写す(曲構成, { 種類: '削除', 位置 })
        assert.deepEqual(写し, { 種類: '積む', コマンド: { 種類: '曲の節を削除する', 値: { 節の位置: 1 } }, 操作の後の選択: null })
    })

    it('複製は曲の節を変えるで繰り返し回数を1増やし、選択を元の位置(小節の番号含む)のまま保つ', () => {
        const 位置 = { 節の位置: 1, 繰り返しの何回目: 0, 小節の番号: 0 }
        const 写し = カードの操作をコマンドへ写す(曲構成, { 種類: '複製', 位置 })
        assert.deepEqual(写し, { 種類: '積む', コマンド: { 種類: '曲の節を変える', 値: { 節の位置: 1, 新しいパターンの名乗り: 'b', 新しい繰り返し回数: 2 } }, 操作の後の選択: 位置 })
    })

    it('複製は繰り返し回数が上限ならできない', () => {
        const 位置 = { 節の位置: 2, 繰り返しの何回目: 0, 小節の番号: 0 }
        assert.equal(カードの操作をコマンドへ写す(曲構成, { 種類: '複製', 位置 }).種類, 'できない')
    })

    it('位置の節が存在しないときは失敗させる', () => {
        const 位置 = { 節の位置: 99, 繰り返しの何回目: 0, 小節の番号: 0 }
        assert.throws(() => カードの操作をコマンドへ写す(曲構成, { 種類: '削除', 位置 }))
    })
})
