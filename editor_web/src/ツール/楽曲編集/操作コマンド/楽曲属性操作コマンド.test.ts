import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { 楽曲編集コマンド } from '../../../生成/編集資源契約.ts'
import { 楽曲編集状態 } from '../編集モデル/index.ts'
import { 楽曲編集コマンドを適用する, 差し戻しを適用する } from './index.ts'

describe('楽曲属性操作コマンドの適用と差し戻しテスト', () => {
    function 状態の同一性を検証する(状態: 楽曲編集状態, 元状態: 楽曲編集状態, コマンド名: string): void {
        assert.deepEqual(状態.楽曲, 元状態.楽曲, `${コマンド名} の適用後に差し戻した楽曲データが完全一致すること`)
    }

    it('6. 拍毎分を変える の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: '拍毎分を変える',
            値: { 新しい拍毎分: 140 },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.楽曲.拍毎分, 140)
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, '拍毎分を変える')
    })

    it('7. ミキサー設定を変える の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: 'ミキサー設定を変える',
            値: { 新しいミキサー設定: { 全体の音量: 0.8, 残響の量: 0.5, 遅延の量: 0.2, 遅延のステップ数: 4 } },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.deepEqual(状態.楽曲.ミキサー設定, コマンド.値.新しいミキサー設定)
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, 'ミキサー設定を変える')
    })

    it('8. 楽曲の表示名を変える の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: '楽曲の表示名を変える',
            値: { 新しい表示名: 'タイトル曲' },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.楽曲.表示名, 'タイトル曲')
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, '楽曲の表示名を変える')
    })

    it('9. トラックの楽器を変える の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: 'トラックの楽器を変える',
            値: { トラックの位置: 0, 新しい楽器: '弦楽合奏' },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.楽曲.トラック構成[0]?.楽器, '弦楽合奏')
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, 'トラックの楽器を変える')
    })

    it('10. トラックの音量を変える の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: 'トラックの音量を変える',
            値: { トラックの位置: 1, 新しい音量: 0.5 },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.楽曲.トラック構成[1]?.音量, 0.5)
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, 'トラックの音量を変える')
    })

    it('11. トラックの進行の割り当てを変える の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: 'トラックの進行の割り当てを変える',
            値: { トラックの位置: 2, 新しい進行の割り当て: { 種類: '既定の進行', 識別子: '王道進行' } },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.deepEqual(状態.楽曲.トラック構成[2]?.進行の割り当て, { 種類: '既定の進行', 識別子: '王道進行' })
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, 'トラックの進行の割り当てを変える')
    })
})
