import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { 打ち込みの対象, 楽曲編集コマンド } from '../../../生成/編集資源契約.ts'
import { パターンのステップ数 } from '../../../生成/編集資源契約.ts'
import { 楽曲編集状態 } from '../編集モデル/index.ts'
import { 楽曲編集コマンドを適用する, 差し戻しを適用する } from './index.ts'

const 先頭の行: 打ち込みの対象 = { パターンの名乗り: 'pattern-1', トラックの位置: 0, 行の位置: 0 }

function 格子が全部打点なしか(状態: 楽曲編集状態): boolean {
    const 行 = 状態.パターンを取得する('pattern-1').格子[0]?.行一覧[0]
    return 行 !== undefined && 行.every((値) => 値 === 0)
}

describe('格子の範囲の外を指すコマンドの拒否', () => {
    it('格子の外のステップへ打点を置くコマンドは失敗する', () => {
        const 状態 = new 楽曲編集状態()
        const コマンド: 楽曲編集コマンド = {
            種類: '打点を置く',
            値: { 対象: 先頭の行, ステップ: パターンのステップ数, 進行に従うか: true },
        }
        assert.throws(() => 楽曲編集コマンドを適用する(状態, コマンド), /ステップが格子の行の外です/)
    })

    it('格子の外のステップの打点を消すコマンドは失敗する', () => {
        const 状態 = new 楽曲編集状態()
        const コマンド: 楽曲編集コマンド = {
            種類: '打点を消す',
            値: { 対象: 先頭の行, ステップ: -1 },
        }
        assert.throws(() => 楽曲編集コマンドを適用する(状態, コマンド), /ステップが格子の行の外です/)
    })

    it('終わりが格子の外の音を伸ばすコマンドは、格子を書き換える前に失敗する', () => {
        const 状態 = new 楽曲編集状態()
        const コマンド: 楽曲編集コマンド = {
            種類: '音を伸ばす',
            値: {
                対象: 先頭の行,
                始まりのステップ: パターンのステップ数 - 2,
                終わりのステップ: パターンのステップ数,
                進行に従うか: true,
            },
        }
        assert.throws(() => 楽曲編集コマンドを適用する(状態, コマンド), /ステップが格子の行の外です/)
        assert.equal(格子が全部打点なしか(状態), true)
    })

    it('終わりが格子の外の範囲の打点を消すコマンドは、格子を書き換える前に失敗する', () => {
        const 状態 = new 楽曲編集状態()
        楽曲編集コマンドを適用する(状態, {
            種類: '打点を置く',
            値: { 対象: 先頭の行, ステップ: パターンのステップ数 - 1, 進行に従うか: true },
        })
        const コマンド: 楽曲編集コマンド = {
            種類: '範囲の打点を消す',
            値: { 対象: 先頭の行, 始まりのステップ: 0, 終わりのステップ: パターンのステップ数 },
        }
        assert.throws(() => 楽曲編集コマンドを適用する(状態, コマンド), /ステップが格子の行の外です/)
        assert.equal(状態.パターンを取得する('pattern-1').格子[0]?.行一覧[0]?.[パターンのステップ数 - 1], 1)
    })

    it('存在しないトラックの位置を指すコマンドは失敗する', () => {
        const 状態 = new 楽曲編集状態()
        const コマンド: 楽曲編集コマンド = {
            種類: '打点を置く',
            値: { 対象: { ...先頭の行, トラックの位置: 99 }, ステップ: 0, 進行に従うか: true },
        }
        assert.throws(() => 楽曲編集コマンドを適用する(状態, コマンド), /格子のトラックがありません/)
    })

    it('存在しない行の位置を指す差し戻しは失敗する', () => {
        const 状態 = new 楽曲編集状態()
        assert.throws(
            () => 差し戻しを適用する(状態, {
                種類: '打点を置く',
                対象: { ...先頭の行, 行の位置: 99 },
                ステップ: 0,
                変更前値: 0,
            }),
            /格子の行がありません/,
        )
    })
})
