import type { 打点を消す, 打点を置く } from '../../../生成/編集資源契約.ts'
import type { 楽曲編集状態 } from '../編集モデル/index.ts'
import type { 打点を消す差し戻し, 打点を置く差し戻し } from './差し戻し断片.ts'

export function 打点を置くコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 打点を置く,
): 打点を置く差し戻し {
    const パターン = 状態.パターンを取得する(コマンド.対象.パターンの名乗り)
    const トラック格子 = パターン.格子[コマンド.対象.トラックの位置]
    const 行 = トラック格子?.行一覧[コマンド.対象.行の位置]
    if (行 === undefined) {
        throw new Error(`対象の格子行が見つかりません`)
    }
    const 変更前値 = 行[コマンド.ステップ] ?? 0
    行[コマンド.ステップ] = コマンド.進行に従うか ? 1 : 3
    return {
        種類: '打点を置く',
        対象: { ...コマンド.対象 },
        ステップ: コマンド.ステップ,
        変更前値,
    }
}

export function 打点を消すコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 打点を消す,
): 打点を消す差し戻し {
    const パターン = 状態.パターンを取得する(コマンド.対象.パターンの名乗り)
    const トラック格子 = パターン.格子[コマンド.対象.トラックの位置]
    const 行 = トラック格子?.行一覧[コマンド.対象.行の位置]
    if (行 === undefined) {
        throw new Error(`対象の格子行が見つかりません`)
    }
    const 変更前値 = 行[コマンド.ステップ] ?? 0
    行[コマンド.ステップ] = 0
    return {
        種類: '打点を消す',
        対象: { ...コマンド.対象 },
        ステップ: コマンド.ステップ,
        変更前値,
    }
}
