import type { 打点を消す, 打点を置く } from '../../../生成/編集資源契約.ts'
import { セルを数値へ変換する, type 楽曲編集状態 } from '../編集モデル/index.ts'
import type { 打点を消す差し戻し, 打点を置く差し戻し } from './差し戻し断片.ts'

export function 打点を置くコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 打点を置く,
): 打点を置く差し戻し {
    const 行 = 状態.打ち込み先の行を取得する(コマンド.対象)
    const 変更前値 = 行.ステップのセルの数値を読む(コマンド.ステップ)
    行.ステップのセルの数値を書き換える(
        コマンド.ステップ,
        セルを数値へ変換する({ 種類: '音の始まり', 進行に従うか: コマンド.進行に従うか }),
    )
    return {
        種類: '打点を置く',
        対象: { ...コマンド.対象 },
        ステップ: コマンド.ステップ,
        変更前値,
    }
}

export function 打点を消すコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 打点を消す,
): 打点を消す差し戻し {
    const 行 = 状態.打ち込み先の行を取得する(コマンド.対象)
    const 変更前値 = 行.ステップのセルの数値を読む(コマンド.ステップ)
    行.ステップのセルの数値を書き換える(コマンド.ステップ, セルを数値へ変換する({ 種類: '打点なし' }))
    return {
        種類: '打点を消す',
        対象: { ...コマンド.対象 },
        ステップ: コマンド.ステップ,
        変更前値,
    }
}
