import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { 曲の節 } from '../../../生成/編集資源契約.ts'
import { カードの操作をコマンドへ写す } from './カードの操作をコマンドへ写す.ts'

describe('カードの操作をコマンドへ写すテスト(挿入・移動)', () => {
    const 曲構成: readonly 曲の節[] = [
        { パターンの名乗り: 'a', 繰り返し回数: 2 },
        { パターンの名乗り: 'b', 繰り返し回数: 1 },
        { パターンの名乗り: 'c', 繰り返し回数: 8 },
    ]

    it('前へ挿入は同じパターンを1回分そのカードの節の位置へ挿入し、元のカードを1つ後ろの節(小節の番号は元のまま)へ移す', () => {
        const 位置 = { 節の位置: 1, 繰り返しの何回目: 0, 小節の番号: 2 }
        const 写し = カードの操作をコマンドへ写す(曲構成, { 種類: '前へ挿入', 位置 })
        assert.deepEqual(写し, { 種類: '積む', コマンド: { 種類: '曲の節を挿入する', 値: { 節の位置: 1, パターンの名乗り: 'b', 繰り返し回数: 1 } }, 操作の後の選択: { 節の位置: 2, 繰り返しの何回目: 0, 小節の番号: 2 } })
    })

    it('後へ挿入は同じパターンを1回分節の位置+1へ挿入し、選択を元の位置(小節の番号含む)のまま保つ', () => {
        const 位置 = { 節の位置: 1, 繰り返しの何回目: 0, 小節の番号: 2 }
        const 写し = カードの操作をコマンドへ写す(曲構成, { 種類: '後へ挿入', 位置 })
        assert.deepEqual(写し, { 種類: '積む', コマンド: { 種類: '曲の節を挿入する', 値: { 節の位置: 2, パターンの名乗り: 'b', 繰り返し回数: 1 } }, 操作の後の選択: 位置 })
    })

    it('前へ移動は曲の節を並べ替えるへ写し、選択を1つ前の節へ移す(小節の番号は元のまま)', () => {
        const 位置 = { 節の位置: 1, 繰り返しの何回目: 0, 小節の番号: 3 }
        const 写し = カードの操作をコマンドへ写す(曲構成, { 種類: '前へ移動', 位置 })
        assert.deepEqual(写し, { 種類: '積む', コマンド: { 種類: '曲の節を並べ替える', 値: { 元の位置: 1, 先の位置: 0 } }, 操作の後の選択: { 節の位置: 0, 繰り返しの何回目: 0, 小節の番号: 3 } })
    })

    it('前へ移動は先頭の節ならできない', () => {
        const 位置 = { 節の位置: 0, 繰り返しの何回目: 0, 小節の番号: 0 }
        assert.equal(カードの操作をコマンドへ写す(曲構成, { 種類: '前へ移動', 位置 }).種類, 'できない')
    })

    it('後へ移動は曲の節を並べ替えるへ写し、選択を1つ後ろの節へ移す(小節の番号は元のまま)', () => {
        const 位置 = { 節の位置: 0, 繰り返しの何回目: 0, 小節の番号: 4 }
        const 写し = カードの操作をコマンドへ写す(曲構成, { 種類: '後へ移動', 位置 })
        assert.deepEqual(写し, { 種類: '積む', コマンド: { 種類: '曲の節を並べ替える', 値: { 元の位置: 0, 先の位置: 1 } }, 操作の後の選択: { 節の位置: 1, 繰り返しの何回目: 0, 小節の番号: 4 } })
    })

    it('後へ移動は末尾の節ならできない', () => {
        const 位置 = { 節の位置: 2, 繰り返しの何回目: 0, 小節の番号: 0 }
        assert.equal(カードの操作をコマンドへ写す(曲構成, { 種類: '後へ移動', 位置 }).種類, 'できない')
    })

    it('複製・挿入・移動は繰り返しの何回目と小節の番号を保ったまま選択を移す', () => {
        const 位置 = { 節の位置: 2, 繰り返しの何回目: 3, 小節の番号: 5 }
        const 選択 = (種類: '前へ挿入' | '後へ挿入' | '前へ移動') => カードの操作をコマンドへ写す(曲構成, { 種類, 位置 })
        assert.deepEqual(選択('前へ移動'), { 種類: '積む', コマンド: { 種類: '曲の節を並べ替える', 値: { 元の位置: 2, 先の位置: 1 } }, 操作の後の選択: { 節の位置: 1, 繰り返しの何回目: 3, 小節の番号: 5 } })
        assert.partialDeepStrictEqual(選択('前へ挿入'), { 操作の後の選択: { 節の位置: 3, 繰り返しの何回目: 3, 小節の番号: 5 } })
        assert.partialDeepStrictEqual(選択('後へ挿入'), { 操作の後の選択: 位置 })
    })
})
