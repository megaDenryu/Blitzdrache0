export function トラックの進行の割り当てを変えるコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: トラックの進行の割り当てを変える,
): トラックの進行の割り当てを変える差し戻し {
    const トラック = 状態.楽曲.トラック構成[コマンド.トラックの位置]
    if (トラック === undefined) {
        throw new Error(`指定位置のトラックが存在しません: ${コマンド.トラックの位置}`)
    }
    const 変更前進行の割り当て = トラック.進行の割り当て ? { ...トラック.進行の割り当て } : null
    トラック.進行の割り当て = コマンド.新しい進行の割り当て ? { ...コマンド.新しい進行の割り当て } : null
    return {
        種類: 'トラックの進行の割り当てを変える',
        トラックの位置: コマンド.トラックの位置,
        変更前進行の割り当て,
    }
}
