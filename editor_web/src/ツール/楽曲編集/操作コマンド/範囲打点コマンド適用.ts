import type {
    パターンの打点を全部消す,
    範囲の打点を消す,
    音を伸ばす,
} from '../../../生成/編集資源契約.ts'
import { セルを数値へ変換する, type 楽曲編集状態 } from '../編集モデル/index.ts'
import type {
    パターンの打点を全部消す差し戻し,
    範囲の打点を消す差し戻し,
    音を伸ばす差し戻し,
} from './差し戻し断片.ts'

export function 音を伸ばすコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 音を伸ばす,
): 音を伸ばす差し戻し {
    const 行 = 状態.打ち込み先の行を取得する(コマンド.対象)
    const 開始 = Math.min(コマンド.始まりのステップ, コマンド.終わりのステップ)
    const 終了 = Math.max(コマンド.始まりのステップ, コマンド.終わりのステップ)
    // 範囲の全ステップを先に読むことで、範囲の外を含むコマンドが格子を書き換える前に失敗する。
    const 変更前値一覧 = 行.範囲のセルの数値を読む(開始, 終了)
    for (let ステップ = 開始; ステップ <= 終了; ステップ++) {
        行.ステップのセルの数値を書き換える(
            ステップ,
            セルを数値へ変換する({
                種類: ステップ === 開始 ? '音の始まり' : '音の継続',
                進行に従うか: コマンド.進行に従うか,
            }),
        )
    }
    return {
        種類: '音を伸ばす',
        対象: { ...コマンド.対象 },
        始まりのステップ: 開始,
        変更前値一覧,
    }
}

export function 範囲の打点を消すコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 範囲の打点を消す,
): 範囲の打点を消す差し戻し {
    const 行 = 状態.打ち込み先の行を取得する(コマンド.対象)
    const 開始 = Math.min(コマンド.始まりのステップ, コマンド.終わりのステップ)
    const 終了 = Math.max(コマンド.始まりのステップ, コマンド.終わりのステップ)
    const 変更前値一覧 = 行.範囲のセルの数値を読む(開始, 終了)
    for (let ステップ = 開始; ステップ <= 終了; ステップ++) {
        行.ステップのセルの数値を書き換える(ステップ, セルを数値へ変換する({ 種類: '打点なし' }))
    }
    return {
        種類: '範囲の打点を消す',
        対象: { ...コマンド.対象 },
        始まりのステップ: 開始,
        変更前値一覧,
    }
}

export function パターンの打点を全部消すコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: パターンの打点を全部消す,
): パターンの打点を全部消す差し戻し {
    const パターン = 状態.パターンを取得する(コマンド.パターンの名乗り)
    const 変更前格子 = パターン.格子.map((トラック格子) => ({
        行一覧: トラック格子.行一覧.map((行) => [...行]),
    }))
    for (const トラック格子 of パターン.格子) {
        for (const 行 of トラック格子.行一覧) {
            行.fill(0)
        }
    }
    return {
        種類: 'パターンの打点を全部消す',
        パターンの名乗り: コマンド.パターンの名乗り,
        変更前格子,
    }
}
