import type {
    パターンの打点を全部消す,
    範囲の打点を消す,
    音を伸ばす,
} from '../../../生成/編集資源契約.ts'
import type { 楽曲編集状態 } from '../編集モデル/index.ts'
import type {
    パターンの打点を全部消す差し戻し,
    範囲の打点を消す差し戻し,
    音を伸ばす差し戻し,
} from './差し戻し断片.ts'

export function 音を伸ばすコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 音を伸ばす,
): 音を伸ばす差し戻し {
    const パターン = 状態.パターンを取得する(コマンド.対象.パターンの名乗り)
    const トラック格子 = パターン.格子[コマンド.対象.トラックの位置]
    const 行 = トラック格子?.行一覧[コマンド.対象.行の位置]
    if (行 === undefined) {
        throw new Error(`対象の格子行が見つかりません`)
    }
    const 変更前値一覧: number[] = []
    const 開始 = Math.min(コマンド.始まりのステップ, コマンド.終わりのステップ)
    const 終了 = Math.max(コマンド.始まりのステップ, コマンド.終わりのステップ)
    for (let s = 開始; s <= 終了; s++) {
        変更前値一覧.push(行[s] ?? 0)
        行[s] = s === 開始 ? (コマンド.進行に従うか ? 1 : 3) : コマンド.進行に従うか ? 2 : 4
    }
    return {
        種類: '音を伸ばす',
        対象: { ...コマンド.対象 },
        始まりのステップ: 開始,
        変更前値一覧,
    }
}

export function 範囲の打点を消すコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 範囲の打点を消す,
): 範囲の打点を消す差し戻し {
    const パターン = 状態.パターンを取得する(コマンド.対象.パターンの名乗り)
    const トラック格子 = パターン.格子[コマンド.対象.トラックの位置]
    const 行 = トラック格子?.行一覧[コマンド.対象.行の位置]
    if (行 === undefined) {
        throw new Error(`対象の格子行が見つかりません`)
    }
    const 変更前値一覧: number[] = []
    const 開始 = Math.min(コマンド.始まりのステップ, コマンド.終わりのステップ)
    const 終了 = Math.max(コマンド.始まりのステップ, コマンド.終わりのステップ)
    for (let s = 開始; s <= 終了; s++) {
        変更前値一覧.push(行[s] ?? 0)
        行[s] = 0
    }
    return {
        種類: '範囲の打点を消す',
        対象: { ...コマンド.対象 },
        始まりのステップ: 開始,
        変更前値一覧,
    }
}

export function パターンの打点を全部消すコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: パターンの打点を全部消す,
): パターンの打点を全部消す差し戻し {
    const パターン = 状態.パターンを取得する(コマンド.パターンの名乗り)
    const 変更前格子 = パターン.格子.map((トラック格子) => ({
        行一覧: トラック格子.行一覧.map((行) => [...行]),
    }))
    for (const トラック格子 of パターン.格子) {
        for (const 行 of トラック格子.行一覧) {
            行.fill(0)
        }
    }
    return {
        種類: 'パターンの打点を全部消す',
        パターンの名乗り: コマンド.パターンの名乗り,
        変更前格子,
    }
}
