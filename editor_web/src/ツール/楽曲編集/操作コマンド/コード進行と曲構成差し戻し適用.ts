import type { 楽曲編集状態 } from '../編集モデル/index.ts'
import type { コード進行と曲構成差し戻し断片 } from './差し戻し断片/コード進行と曲構成差し戻し.ts'

export function コード進行と曲構成差し戻しを適用する(
    状態: 楽曲編集状態,
    断片: コード進行と曲構成差し戻し断片,
): void {
    switch (断片.種類) {
        case '独自の進行を保存する': {
            if (断片.変更前進行 === null || 断片.元の位置 === null) {
                状態.楽曲.独自進行一覧 = 状態.楽曲.独自進行一覧.filter((p) => p.名前 !== 断片.進行名)
            } else {
                状態.楽曲.独自進行一覧[断片.元の位置] = {
                    名前: 断片.変更前進行.名前,
                    和音一覧: 断片.変更前進行.和音一覧.map((和音) => ({ ...和音 })),
                }
            }
            return
        }
        case '独自の進行を削除する':
            状態.楽曲.独自進行一覧.splice(断片.元の位置, 0, {
                名前: 断片.削除された進行.名前,
                和音一覧: 断片.削除された進行.和音一覧.map((和音) => ({ ...和音 })),
            })
            return
        case '曲の節を追加する':
            状態.楽曲.曲構成.splice(断片.節の位置, 1)
            return
        case '曲の節を挿入する':
            状態.楽曲.曲構成.splice(断片.節の位置, 1)
            return
        case '曲の節を変える':
            状態.楽曲.曲構成[断片.節の位置] = { ...断片.変更前節 }
            return
        case '曲の節を削除する':
            状態.楽曲.曲構成.splice(断片.節の位置, 0, { ...断片.削除された節 })
            return
        case '曲の節を並べ替える': {
            const [節] = 状態.楽曲.曲構成.splice(断片.先の位置, 1)
            if (節) 状態.楽曲.曲構成.splice(断片.元の位置, 0, 節)
            return
        }
    }
    const 網羅性検査: never = 断片
    throw new Error(`未対応のコード進行と曲構成差し戻し断片種類: ${JSON.stringify(網羅性検査)}`)
}
