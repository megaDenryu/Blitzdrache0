import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { 楽曲編集コマンド } from '../../../生成/編集資源契約.ts'
import { 楽曲編集状態 } from '../編集モデル/index.ts'
import { 楽曲編集コマンドを適用する, 差し戻しを適用する } from './index.ts'

describe('曲の節を挿入するコマンドの適用と差し戻しテスト', () => {
    function 状態の同一性を検証する(状態: 楽曲編集状態, 元状態: 楽曲編集状態, コマンド名: string): void {
        assert.deepEqual(状態.楽曲, 元状態.楽曲, `${コマンド名} の適用後に差し戻した楽曲データが完全一致すること`)
    }

    it('22. 曲の節を挿入する(先頭) の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        状態.楽曲.曲構成 = [{ パターンの名乗り: 'pattern-1', 繰り返し回数: 1 }]
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: '曲の節を挿入する',
            値: { 節の位置: 0, パターンの名乗り: 'pattern-1', 繰り返し回数: 1 },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.楽曲.曲構成.length, 2)
        assert.deepEqual(状態.楽曲.曲構成[0], { パターンの名乗り: 'pattern-1', 繰り返し回数: 1 })
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, '曲の節を挿入する(先頭)')
    })

    it('23. 曲の節を挿入する(途中) の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        楽曲編集コマンドを適用する(状態, {
            種類: 'パターンを追加する',
            値: { 名乗り: 'pattern-2', 表示名: 'パターン2', 進行の参照: { 種類: '既定の進行', 識別子: '王道進行' } },
        })
        状態.楽曲.曲構成 = [
            { パターンの名乗り: 'pattern-1', 繰り返し回数: 1 },
            { パターンの名乗り: 'pattern-2', 繰り返し回数: 1 },
        ]
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: '曲の節を挿入する',
            値: { 節の位置: 1, パターンの名乗り: 'pattern-2', 繰り返し回数: 3 },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.楽曲.曲構成.length, 3)
        assert.deepEqual(状態.楽曲.曲構成[1], { パターンの名乗り: 'pattern-2', 繰り返し回数: 3 })
        assert.equal(状態.楽曲.曲構成[2]?.パターンの名乗り, 'pattern-2')
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, '曲の節を挿入する(途中)')
    })

    it('24. 曲の節を挿入する(長さと同じ位置=末尾) の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        状態.楽曲.曲構成 = [{ パターンの名乗り: 'pattern-1', 繰り返し回数: 1 }]
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: '曲の節を挿入する',
            値: { 節の位置: 1, パターンの名乗り: 'pattern-1', 繰り返し回数: 2 },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.楽曲.曲構成.length, 2)
        assert.deepEqual(状態.楽曲.曲構成[1], { パターンの名乗り: 'pattern-1', 繰り返し回数: 2 })
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, '曲の節を挿入する(末尾)')
    })

    it('25. 曲の節を挿入する は長さより大きい位置を拒否する', () => {
        const 状態 = new 楽曲編集状態()
        状態.楽曲.曲構成 = [{ パターンの名乗り: 'pattern-1', 繰り返し回数: 1 }]
        const コマンド: 楽曲編集コマンド = {
            種類: '曲の節を挿入する',
            値: { 節の位置: 2, パターンの名乗り: 'pattern-1', 繰り返し回数: 1 },
        }
        assert.throws(() => 楽曲編集コマンドを適用する(状態, コマンド))
    })
})
