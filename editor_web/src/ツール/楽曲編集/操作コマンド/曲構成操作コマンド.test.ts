import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { 楽曲編集コマンド } from '../../../生成/編集資源契約.ts'
import { 楽曲編集状態 } from '../編集モデル/index.ts'
import { 楽曲編集コマンドを適用する, 差し戻しを適用する } from './index.ts'

describe('曲構成操作コマンドの適用と差し戻しテスト', () => {
    function 状態の同一性を検証する(状態: 楽曲編集状態, 元状態: 楽曲編集状態, コマンド名: string): void {
        assert.deepEqual(状態.楽曲, 元状態.楽曲, `${コマンド名} の適用後に差し戻した楽曲データが完全一致すること`)
    }

    it('18. 曲の節を追加する の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: '曲の節を追加する',
            値: { パターンの名乗り: 'pattern-1', 繰り返し回数: 2 },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.楽曲.曲構成.length, 1)
        assert.deepEqual(状態.楽曲.曲構成[0], { パターンの名乗り: 'pattern-1', 繰り返し回数: 2 })
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, '曲の節を追加する')
    })

    it('19. 曲の節を変える の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        状態.楽曲.曲構成 = [{ パターンの名乗り: 'pattern-1', 繰り返し回数: 1 }]
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: '曲の節を変える',
            値: { 節の位置: 0, 新しいパターンの名乗り: 'pattern-1', 新しい繰り返し回数: 4 },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.楽曲.曲構成[0]?.繰り返し回数, 4)
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, '曲の節を変える')
    })

    it('20. 曲の節を削除する の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        状態.楽曲.曲構成 = [{ パターンの名乗り: 'pattern-1', 繰り返し回数: 1 }]
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: '曲の節を削除する',
            値: { 節の位置: 0 },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.楽曲.曲構成.length, 0)
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, '曲の節を削除する')
    })

    it('21. 曲の節を並べ替える の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        楽曲編集コマンドを適用する(状態, {
            種類: 'パターンを追加する',
            値: { 名乗り: 'pattern-2', 小節数: 2, 表示名: 'パターン2', 進行の参照: { 種類: '既定の進行', 識別子: '王道進行' } },
        })
        状態.楽曲.曲構成 = [
            { パターンの名乗り: 'pattern-1', 繰り返し回数: 1 },
            { パターンの名乗り: 'pattern-2', 繰り返し回数: 2 },
        ]
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: '曲の節を並べ替える',
            値: { 元の位置: 0, 先の位置: 1 },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.楽曲.曲構成[0]?.パターンの名乗り, 'pattern-2')
        assert.equal(状態.楽曲.曲構成[1]?.パターンの名乗り, 'pattern-1')
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, '曲の節を並べ替える')
    })
})
