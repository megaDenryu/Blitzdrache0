import { 曲の節の繰り返し回数の上限, type 曲の節, type 楽曲編集コマンド } from '../../../生成/編集資源契約.ts'
import type { カード位置 } from '../編集モデル/index.ts'

export type カードの操作 =
    | { readonly 種類: '末尾へ追加'; readonly パターンの名乗り: string }
    | { readonly 種類: '削除'; readonly 位置: カード位置 }
    | { readonly 種類: '複製'; readonly 位置: カード位置 }
    | { readonly 種類: '前へ挿入'; readonly 位置: カード位置 }
    | { readonly 種類: '後へ挿入'; readonly 位置: カード位置 }
    | { readonly 種類: '前へ移動'; readonly 位置: カード位置 }
    | { readonly 種類: '後へ移動'; readonly 位置: カード位置 }

export type カードの操作の写し =
    | { readonly 種類: '積む'; readonly コマンド: 楽曲編集コマンド }
    | { readonly 種類: 'できない'; readonly 理由: string }

function コマンドを積む写しへ包む(コマンド: 楽曲編集コマンド): カードの操作の写し {
    return { 種類: '積む', コマンド }
}

// カードが指す節を取り出す。配線の誤りで存在しない位置を渡された場合は失敗させる。
function 指す節を取得する(曲構成: readonly 曲の節[], 節の位置: number): 曲の節 {
    const 節 = 曲構成[節の位置]
    if (節 === undefined) throw new Error(`カードが指す節が存在しません: 節の位置=${節の位置}`)
    return 節
}

function 節の繰り返し回数を変える操作を写す(節の位置: number, 節: 曲の節, 新しい繰り返し回数: number): カードの操作の写し {
    return コマンドを積む写しへ包む({
        種類: '曲の節を変える',
        値: { 節の位置, 新しいパターンの名乗り: 節.パターンの名乗り, 新しい繰り返し回数 },
    })
}

function 削除操作を写す(位置: カード位置, 節: 曲の節): カードの操作の写し {
    if (節.繰り返し回数 >= 2) return 節の繰り返し回数を変える操作を写す(位置.節の位置, 節, 節.繰り返し回数 - 1)
    return コマンドを積む写しへ包む({ 種類: '曲の節を削除する', 値: { 節の位置: 位置.節の位置 } })
}

function 複製操作を写す(位置: カード位置, 節: 曲の節): カードの操作の写し {
    if (節.繰り返し回数 >= 曲の節の繰り返し回数の上限) {
        return { 種類: 'できない', 理由: `繰り返し回数が上限(${曲の節の繰り返し回数の上限})に達しています` }
    }
    return 節の繰り返し回数を変える操作を写す(位置.節の位置, 節, 節.繰り返し回数 + 1)
}

function 挿入操作を写す(挿入先の節の位置: number, 節: 曲の節): カードの操作の写し {
    return コマンドを積む写しへ包む({
        種類: '曲の節を挿入する',
        値: { 節の位置: 挿入先の節の位置, パターンの名乗り: 節.パターンの名乗り, 繰り返し回数: 1 },
    })
}

function 移動操作を写す(元の位置: number, 先の位置: number, 曲構成の長さ: number, 拒否理由: string): カードの操作の写し {
    if (先の位置 < 0 || 先の位置 >= 曲構成の長さ) return { 種類: 'できない', 理由: 拒否理由 }
    return コマンドを積む写しへ包む({ 種類: '曲の節を並べ替える', 値: { 元の位置, 先の位置 } })
}

// カードでの操作を、そのカードを含む節の操作コマンドへ写す(設計正本`_doc/設計/楽曲エディター.md`判断15の表)。
export function カードの操作をコマンドへ写す(曲構成: readonly 曲の節[], 操作: カードの操作): カードの操作の写し {
    switch (操作.種類) {
        case '末尾へ追加':
            return コマンドを積む写しへ包む({ 種類: '曲の節を追加する', 値: { パターンの名乗り: 操作.パターンの名乗り, 繰り返し回数: 1 } })
        case '削除':
            return 削除操作を写す(操作.位置, 指す節を取得する(曲構成, 操作.位置.節の位置))
        case '複製':
            return 複製操作を写す(操作.位置, 指す節を取得する(曲構成, 操作.位置.節の位置))
        case '前へ挿入':
            return 挿入操作を写す(操作.位置.節の位置, 指す節を取得する(曲構成, 操作.位置.節の位置))
        case '後へ挿入':
            return 挿入操作を写す(操作.位置.節の位置 + 1, 指す節を取得する(曲構成, 操作.位置.節の位置))
        case '前へ移動':
            指す節を取得する(曲構成, 操作.位置.節の位置)
            return 移動操作を写す(操作.位置.節の位置, 操作.位置.節の位置 - 1, 曲構成.length, '先頭の節はこれ以上前へ移動できません')
        case '後へ移動':
            指す節を取得する(曲構成, 操作.位置.節の位置)
            return 移動操作を写す(操作.位置.節の位置, 操作.位置.節の位置 + 1, 曲構成.length, '末尾の節はこれ以上後へ移動できません')
    }
    const 網羅性検査: never = 操作
    throw new Error(`未対応のカードの操作種類: ${JSON.stringify(網羅性検査)}`)
}
