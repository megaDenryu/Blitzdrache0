import {
    曲の節の繰り返し回数の下限,
    type 曲の節を追加する,
    type 曲の節を挿入する,
} from '../../../生成/編集資源契約.ts'
import type { 楽曲編集状態 } from '../編集モデル/index.ts'
import type {
    曲の節を追加する差し戻し,
    曲の節を挿入する差し戻し,
} from './差し戻し断片.ts'

export function 曲の節を追加するコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 曲の節を追加する,
): 曲の節を追加する差し戻し {
    if (!状態.パターンが存在するか(コマンド.パターンの名乗り)) {
        throw new Error(`指定されたパターンが存在しません: ${コマンド.パターンの名乗り}`)
    }
    状態.楽曲.曲構成.push({
        パターンの名乗り: コマンド.パターンの名乗り,
        繰り返し回数: Math.max(曲の節の繰り返し回数の下限, コマンド.繰り返し回数),
    })
    return {
        種類: '曲の節を追加する',
        節の位置: 状態.楽曲.曲構成.length - 1,
    }
}

// 節の位置の手前へ差し込む。位置が曲構成の長さと等しいなら末尾へ足すのと同じになる。
export function 曲の節を挿入するコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: 曲の節を挿入する,
): 曲の節を挿入する差し戻し {
    const 節数 = 状態.楽曲.曲構成.length
    if (コマンド.節の位置 < 0 || コマンド.節の位置 > 節数) {
        throw new Error(`挿入位置が範囲外です: ${コマンド.節の位置}`)
    }
    if (!状態.パターンが存在するか(コマンド.パターンの名乗り)) {
        throw new Error(`指定されたパターンが存在しません: ${コマンド.パターンの名乗り}`)
    }
    状態.楽曲.曲構成.splice(コマンド.節の位置, 0, {
        パターンの名乗り: コマンド.パターンの名乗り,
        繰り返し回数: Math.max(曲の節の繰り返し回数の下限, コマンド.繰り返し回数),
    })
    return {
        種類: '曲の節を挿入する',
        節の位置: コマンド.節の位置,
    }
}
