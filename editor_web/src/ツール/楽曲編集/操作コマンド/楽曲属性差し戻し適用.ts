import type { 楽曲編集状態 } from '../編集モデル/index.ts'
import type { 楽曲属性差し戻し断片 } from './差し戻し断片/楽曲属性差し戻し.ts'

export function 楽曲属性差し戻しを適用する(
    状態: 楽曲編集状態,
    断片: 楽曲属性差し戻し断片,
): void {
    switch (断片.種類) {
        case 'テンポを変える':
            状態.楽曲.テンポ = 断片.変更前テンポ
            return
        case 'ミキサー設定を変える':
            状態.楽曲.ミキサー設定 = { ...断片.変更前ミキサー設定 }
            return
        case '楽曲の表示名を変える':
            状態.楽曲.表示名 = 断片.変更前表示名
            return
        case 'トラックの楽器を変える':
            if (状態.楽曲.トラック構成[断片.トラックの位置]) {
                状態.楽曲.トラック構成[断片.トラックの位置].楽器 = 断片.変更前楽器
            }
            return
        case 'トラックの音量を変える':
            if (状態.楽曲.トラック構成[断片.トラックの位置]) {
                状態.楽曲.トラック構成[断片.トラックの位置].音量 = 断片.変更前音量
            }
            return
        case 'トラックの進行の割り当てを変える':
            if (状態.楽曲.トラック構成[断片.トラックの位置]) {
                状態.楽曲.トラック構成[断片.トラックの位置].進行の割り当て = 断片.変更前進行の割り当て
                    ? { ...断片.変更前進行の割り当て }
                    : null
            }
            return
    }
    const 網羅性検査: never = 断片
    throw new Error(`未対応の楽曲属性差し戻し断片種類: ${JSON.stringify(網羅性検査)}`)
}
