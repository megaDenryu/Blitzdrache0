import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { 楽曲編集コマンド } from '../../../生成/編集資源契約.ts'
import { 楽曲編集状態 } from '../編集モデル/index.ts'
import { 楽曲編集コマンドを適用する, 差し戻しを適用する } from './index.ts'

describe('打ち込み操作コマンドの適用と差し戻しテスト', () => {
    function 状態の同一性を検証する(状態: 楽曲編集状態, 元状態: 楽曲編集状態, コマンド名: string): void {
        assert.deepEqual(状態.楽曲, 元状態.楽曲, `${コマンド名} の適用後に差し戻した楽曲データが完全一致すること`)
    }

    it('1. 打点を置く の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: '打点を置く',
            値: { 対象: { パターンの名乗り: 'pattern-1', トラックの位置: 0, 行の位置: 0 }, ステップ: 4, 進行に従うか: true },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.パターンを取得する('pattern-1').格子[0]?.行一覧[0]?.[4], 1)
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, '打点を置く')
    })

    it('2. 打点を消す の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        const パターン = 状態.パターンを取得する('pattern-1')
        const 行 = パターン.格子[0]?.行一覧[0]
        if (行) 行[4] = 1
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: '打点を消す',
            値: { 対象: { パターンの名乗り: 'pattern-1', トラックの位置: 0, 行の位置: 0 }, ステップ: 4 },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.パターンを取得する('pattern-1').格子[0]?.行一覧[0]?.[4], 0)
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, '打点を消す')
    })

    it('3. 音を伸ばす の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: '音を伸ばす',
            値: { 対象: { パターンの名乗り: 'pattern-1', トラックの位置: 0, 行の位置: 0 }, 始まりのステップ: 0, 終わりのステップ: 3, 進行に従うか: true },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        const 行 = 状態.パターンを取得する('pattern-1').格子[0]?.行一覧[0]
        assert.deepEqual(行?.slice(0, 4), [1, 2, 2, 2])
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, '音を伸ばす')
    })

    it('4. 範囲の打点を消す の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        const パターン = 状態.パターンを取得する('pattern-1')
        const 行 = パターン.格子[0]?.行一覧[0]
        if (行) {
            行[0] = 1; 行[1] = 2; 行[2] = 2; 行[3] = 2
        }
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: '範囲の打点を消す',
            値: { 対象: { パターンの名乗り: 'pattern-1', トラックの位置: 0, 行の位置: 0 }, 始まりのステップ: 0, 終わりのステップ: 3 },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.deepEqual(状態.パターンを取得する('pattern-1').格子[0]?.行一覧[0]?.slice(0, 4), [0, 0, 0, 0])
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, '範囲の打点を消す')
    })

    it('5. パターンの打点を全部消す の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        const パターン = 状態.パターンを取得する('pattern-1')
        if (パターン.格子[0]?.行一覧[0]) パターン.格子[0].行一覧[0][0] = 1
        if (パターン.格子[1]?.行一覧[1]) パターン.格子[1].行一覧[1][5] = 3
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: 'パターンの打点を全部消す',
            値: { パターンの名乗り: 'pattern-1' },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.パターンを取得する('pattern-1').格子[0]?.行一覧[0]?.[0], 0)
        assert.equal(状態.パターンを取得する('pattern-1').格子[1]?.行一覧[1]?.[5], 0)
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, 'パターンの打点を全部消す')
    })
})
