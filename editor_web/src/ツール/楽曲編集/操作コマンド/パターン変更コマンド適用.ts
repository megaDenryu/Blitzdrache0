import type {
    パターンの進行を変える,
    パターンの表示名を変える,
} from '../../../生成/編集資源契約.ts'
import {
    パターン格子を進行に合わせて掃除する,
    type 楽曲編集状態,
} from '../編集モデル/index.ts'
import type {
    パターンの進行を変える差し戻し,
    パターンの表示名を変える差し戻し,
} from './差し戻し断片.ts'

export function パターンの進行を変えるコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: パターンの進行を変える,
): パターンの進行を変える差し戻し {
    const 対象パターン = 状態.パターンを取得する(コマンド.名乗り)
    const 変更前進行の参照 = { ...対象パターン.進行の参照 }
    const 変更前格子 = 対象パターン.格子.map((tg) => ({
        行一覧: tg.行一覧.map((row) => [...row]),
    }))
    対象パターン.進行の参照 = { ...コマンド.新しい進行の参照 }
    対象パターン.格子 = パターン格子を進行に合わせて掃除する(
        対象パターン,
        状態.楽曲.トラック構成,
        コマンド.新しい進行の参照,
        状態.楽曲.独自進行一覧,
    )
    return {
        種類: 'パターンの進行を変える',
        名乗り: コマンド.名乗り,
        変更前進行の参照,
        変更前格子,
    }
}

export function パターンの表示名を変えるコマンドを適用する(
    状態: 楽曲編集状態,
    コマンド: パターンの表示名を変える,
): パターンの表示名を変える差し戻し {
    const 対象パターン = 状態.パターンを取得する(コマンド.名乗り)
    const 変更前表示名 = 対象パターン.表示名
    対象パターン.表示名 = コマンド.新しい表示名
    return {
        種類: 'パターンの表示名を変える',
        名乗り: コマンド.名乗り,
        変更前表示名,
    }
}
