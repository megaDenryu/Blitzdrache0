import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { 楽曲編集コマンド } from '../../../生成/編集資源契約.ts'
import { 楽曲編集状態 } from '../編集モデル/index.ts'
import { 楽曲編集コマンドを適用する, 差し戻しを適用する } from './index.ts'

describe('パターン操作コマンドの適用と差し戻しテスト', () => {
    function 状態の同一性を検証する(状態: 楽曲編集状態, 元状態: 楽曲編集状態, コマンド名: string): void {
        assert.deepEqual(状態.楽曲, 元状態.楽曲, `${コマンド名} の適用後に差し戻した楽曲データが完全一致すること`)
    }

    it('12. パターンを追加する の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: 'パターンを追加する',
            値: { 名乗り: 'pattern-2', 表示名: 'サビ', 小節数: 2, 進行の参照: { 種類: '既定の進行', 識別子: '王道進行' } },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.パターンが存在するか('pattern-2'), true)
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, 'パターンを追加する')
    })

    it('パターンを追加する に小節数3を渡すと格子が48列(3小節×16ステップ)になる', () => {
        const 状態 = new 楽曲編集状態()
        楽曲編集コマンドを適用する(状態, {
            種類: 'パターンを追加する',
            値: { 名乗り: 'pattern-3bars', 表示名: '3小節', 小節数: 3, 進行の参照: { 種類: '既定の進行', 識別子: '王道進行' } },
        })
        const パターン = 状態.パターンを取得する('pattern-3bars')
        assert.equal(パターン.小節数, 3)
        for (const トラック格子 of パターン.格子) {
            for (const 行 of トラック格子.行一覧) assert.equal(行.length, 48)
        }
    })

    it('13. パターンを削除する の適用と差し戻し（曲構成の連動削除と復元を含む）', () => {
        const 状態 = new 楽曲編集状態()
        楽曲編集コマンドを適用する(状態, {
            種類: 'パターンを追加する',
            値: { 名乗り: 'pattern-2', 表示名: 'サビ', 小節数: 2, 進行の参照: { 種類: '既定の進行', 識別子: '王道進行' } },
        })
        状態.楽曲.曲構成 = [
            { パターンの名乗り: 'pattern-1', 繰り返し回数: 1 },
            { パターンの名乗り: 'pattern-2', 繰り返し回数: 2 },
            { パターンの名乗り: 'pattern-1', 繰り返し回数: 1 },
        ]
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: 'パターンを削除する',
            値: { 名乗り: 'pattern-2' },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.パターンが存在するか('pattern-2'), false)
        assert.equal(状態.楽曲.曲構成.length, 2)
        assert.equal(状態.楽曲.曲構成.every((節) => 節.パターンの名乗り !== 'pattern-2'), true)

        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, 'パターンを削除する')
    })

    it('14. パターンの進行を変える の適用と差し戻し（格子の自動掃除と復元を含む）', () => {
        const 状態 = new 楽曲編集状態()
        const パターン = 状態.パターンを取得する('pattern-1')
        if (パターン.格子[0]?.行一覧[0]) パターン.格子[0].行一覧[0][0] = 1
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: 'パターンの進行を変える',
            値: { 名乗り: 'pattern-1', 新しい進行の参照: { 種類: '既定の進行', 識別子: '街とやすらぎ' } },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.deepEqual(状態.パターンを取得する('pattern-1').進行の参照, { 種類: '既定の進行', 識別子: '街とやすらぎ' })
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, 'パターンの進行を変える')
    })

    it('15. パターンの表示名を変える の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: 'パターンの表示名を変える',
            値: { 名乗り: 'pattern-1', 新しい表示名: 'イントロ' },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.パターンを取得する('pattern-1').表示名, 'イントロ')
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, 'パターンの表示名を変える')
    })
})
