import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { 楽曲編集コマンド } from '../../../生成/編集資源契約.ts'
import { 楽曲編集状態 } from '../編集モデル/index.ts'
import { 楽曲編集コマンドを適用する, 差し戻しを適用する } from './index.ts'

describe('独自進行操作コマンドの適用と差し戻しテスト', () => {
    function 状態の同一性を検証する(状態: 楽曲編集状態, 元状態: 楽曲編集状態, コマンド名: string): void {
        assert.deepEqual(状態.楽曲, 元状態.楽曲, `${コマンド名} の適用後に差し戻した楽曲データが完全一致すること`)
    }

    it('16. 独自の進行を保存する の適用と差し戻し（新規および上書き）', () => {
        const 状態 = new 楽曲編集状態()
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const 新規コマンド: 楽曲編集コマンド = {
            種類: '独自の進行を保存する',
            値: { 進行: { 名前: 'マイ進行', 和音一覧: [{ 根音: 0, 種類: '長三和音', 続くステップ数: 16 }] } },
        }
        const 断片1 = 楽曲編集コマンドを適用する(状態, 新規コマンド)
        assert.equal(状態.楽曲.独自進行一覧.length, 1)
        assert.equal(状態.楽曲.独自進行一覧[0]?.名前, 'マイ進行')

        const 上書きコマンド: 楽曲編集コマンド = {
            種類: '独自の進行を保存する',
            値: { 進行: { 名前: 'マイ進行', 和音一覧: [{ 根音: 9, 種類: '短三和音', 続くステップ数: 16 }] } },
        }
        const 断片2 = 楽曲編集コマンドを適用する(状態, 上書きコマンド)
        assert.equal(状態.楽曲.独自進行一覧[0]?.和音一覧[0]?.根音, 9)

        差し戻しを適用する(状態, 断片2)
        assert.equal(状態.楽曲.独自進行一覧[0]?.和音一覧[0]?.根音, 0)

        差し戻しを適用する(状態, 断片1)
        状態の同一性を検証する(状態, 元状態, '独自の進行を保存する')
    })

    it('17. 独自の進行を削除する の適用と差し戻し', () => {
        const 状態 = new 楽曲編集状態()
        状態.楽曲.独自進行一覧 = [{ 名前: 'マイ進行', 和音一覧: [{ 根音: 0, 種類: '長三和音', 続くステップ数: 16 }] }]
        const 元状態 = new 楽曲編集状態(状態.楽曲)
        const コマンド: 楽曲編集コマンド = {
            種類: '独自の進行を削除する',
            値: { 名前: 'マイ進行' },
        }
        const 断片 = 楽曲編集コマンドを適用する(状態, コマンド)
        assert.equal(状態.楽曲.独自進行一覧.length, 0)
        差し戻しを適用する(状態, 断片)
        状態の同一性を検証する(状態, 元状態, '独自の進行を削除する')
    })
})
