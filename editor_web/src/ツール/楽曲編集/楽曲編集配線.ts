import type { 楽曲ID } from '../../境界/index.ts'
import type { 楽曲接続 } from '../../境界/通信/index.ts'
import { パネル操作を実行する, type パネル操作結果 } from '../チャンク編集/永続化パネル操作.ts'
import type { 楽曲編集状態 } from './編集モデル/index.ts'
import type { 楽曲編集画面 } from './画面/index.ts'

// 楽曲編集画面の永続化（保存・読込）イベントを、編集モデルと楽曲接続へ配線する。
export function 楽曲編集イベントを配線する(
    画面: 楽曲編集画面,
    状態: 楽曲編集状態,
    接続: 楽曲接続,
    楽曲ID: 楽曲ID,
): () => void {
    const 表示を再構築する = (): void => {
        画面.表示を更新する(状態.楽曲を取得する(), 状態.選択中パターンの名乗り)
    }

    const 保存する = async (): Promise<パネル操作結果> => {
        const 結果 = await 接続.楽曲を保存する(状態.楽曲を取得する())
        if (結果.種別 === '失敗') {
            return { 文言: `保存失敗: ${結果.エラー.種別} ${結果.エラー.説明}`, エラーか: true }
        }
        return { 文言: '保存完了', エラーか: false }
    }

    const 読み込む = async (): Promise<パネル操作結果> => {
        const 結果 = await 接続.楽曲を読む(楽曲ID)
        if (結果.種別 === '失敗') {
            return { 文言: `読込失敗: ${結果.エラー.種別} ${結果.エラー.説明}`, エラーか: true }
        }
        if (結果.種別 === '成功') 状態.状態を上書きする(結果.値)
        表示を再構築する()
        return {
            文言: 結果.種別 === '成功' ? '読み込み完了' : '未保存: 初期楽曲を表示中',
            エラーか: false,
        }
    }

    画面.永続化.on保存クリック(() => {
        void パネル操作を実行する(画面.永続化, '保存中...', 保存する, '保存失敗')
    })
    画面.永続化.on読込クリック(() => {
        void パネル操作を実行する(画面.永続化, '読み込み中...', 読み込む, '読込失敗')
    })

    表示を再構築する()
    return 表示を再構築する
}

// ツール起動時にサーバーから楽曲データを非同期に読み込み、画面へ反映する。
export async function 起動時に楽曲を読み込む(
    画面: 楽曲編集画面,
    状態: 楽曲編集状態,
    接続: 楽曲接続,
    楽曲ID: 楽曲ID,
    表示を再構築する: () => void,
): Promise<void> {
    try {
        const 結果 = await 接続.楽曲を読む(楽曲ID)
        if (結果.種別 === '成功') {
            状態.状態を上書きする(結果.値)
            画面.永続化.状態文言を更新する('読込完了(起動時)', false)
        } else if (結果.種別 === '無し') {
            画面.永続化.状態文言を更新する('未保存: 初期楽曲を表示中', false)
        } else {
            画面.永続化.状態文言を更新する(
                `起動時読込失敗: ${結果.エラー.種別} ${結果.エラー.説明}`,
                true,
            )
        }
    } catch (原因: unknown) {
        const メッセージ = 原因 instanceof Error ? 原因.message : String(原因)
        画面.永続化.状態文言を更新する(`起動時読込失敗: ${メッセージ}`, true)
    }
    表示を再構築する()
}
