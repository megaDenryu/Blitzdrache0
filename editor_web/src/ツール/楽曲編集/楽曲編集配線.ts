export interface 楽曲編集配線の相手 {
    readonly 画面: 楽曲編集画面
    readonly 状態: 楽曲編集状態
    readonly UI状態: 楽曲編集UI状態
    readonly 操作: 楽曲履歴適用サービス
    readonly 接続: 楽曲接続
    readonly 演奏: 演奏サービス
    readonly 同期: 楽曲編集の表示の同期
    readonly 表示名の編集: 表示名の編集をまとめる係
    readonly 楽曲ID: 楽曲ID
}

// 楽曲編集画面のイベント（ポインタ打ち込み・キーボード・楽曲名の欄・演奏の操作帯・パネル群・永続化）を配線する。
export function 楽曲編集イベントを配線する(相手: 楽曲編集配線の相手): () => void {
    const 表示を再構築する = (): void => { 相手.同期.再構築する() }
    const 発音配線 = 相手.画面.発音配線.配線済みか ? 相手.画面.発音配線.先 : undefined
    const 振り分け = new 楽曲編集ポインタ振り分け(
        相手.状態,
        相手.UI状態,
        相手.操作,
        表示を再構築する,
        発音配線,
    )

    相手.画面.升目操作を配線する(
        (当たり, ボタン) => { 振り分け.押された(ボタン, 当たり) },
        (当たり) => { 振り分け.動かされた(当たり) },
    )

    const ポインタ解放処理 = (e: PointerEvent): void => { 振り分け.離された(e.button) }
    const ポインタキャンセル処理 = (): void => { 振り分け.キャンセルされた() }
    window.addEventListener('pointerup', ポインタ解放処理)
    window.addEventListener('pointercancel', ポインタキャンセル処理)

    const キー解除 = 楽曲編集キーボード入力を配線する(相手.UI状態, 相手.操作, 表示を再構築する, 相手.演奏)
    // 打っている間はコマンドを積まず見えだけを追随させ、欄から離れたときに1つだけ積む(判断13)。
    相手.画面.楽曲名.配線する({
        on表示名が入力された: (入力中の表示名) => { 相手.表示名の編集.表示名が入力された(入力中の表示名) },
        on表示名が決まった: (新しい表示名) => { 相手.表示名の編集.表示名の入力が決まった(新しい表示名) },
    })
    楽曲編集パネル群を配線する(相手.画面, 相手.状態, 相手.UI状態, 相手.操作, 表示を再構築する, 相手.演奏)
    相手.画面.タイムライン.配線する(
        new タイムラインハンドラ(相手.状態, 相手.UI状態, 相手.操作, 表示を再構築する),
    )

    const 操作帯ハンドラ = new 演奏の操作帯ハンドラ(相手.画面, 相手.状態, 相手.操作, 相手.演奏)
    相手.画面.操作帯.配線する(操作帯ハンドラ)
    相手.演奏.知らせ役.on再生位置が変わった.配線する(
        new 再生位置の反映(相手.画面, 相手.状態, 相手.UI状態, 相手.演奏, 相手.同期),
    )
    相手.演奏.知らせの口.on演奏の知らせ.配線する(new 演奏の知らせの反映(相手.画面))

    永続化を配線する(相手, 表示を再構築する)

    表示を再構築する()
    操作帯ハンドラ.演奏の様子を画面へ映す()
    return () => {
        window.removeEventListener('pointerup', ポインタ解放処理)
        window.removeEventListener('pointercancel', ポインタキャンセル処理)
        キー解除()
    }
}

// 保存と読み込みの押しどころを、楽曲接続の往復へつなぐ。
function 永続化を配線する(相手: 楽曲編集配線の相手, 表示を再構築する: () => void): void {
    const 保存する = async (): Promise<パネル操作結果> => {
        const 結果 = await 相手.接続.楽曲を保存する(相手.状態.楽曲を取得する())
        if (結果.種別 === '失敗') {
            return { 文言: `保存失敗: ${結果.エラー.種別} ${結果.エラー.説明}`, エラーか: true }
        }
        return { 文言: '保存完了', エラーか: false }
    }

    const 読み込む = async (): Promise<パネル操作結果> => {
        const 結果 = await 相手.接続.楽曲を読む(相手.楽曲ID)
        if (結果.種別 === '失敗') {
            return { 文言: `読込失敗: ${結果.エラー.種別} ${結果.エラー.説明}`, エラーか: true }
        }
        if (結果.種別 === '成功') 相手.状態.状態を上書きする(結果.値)
        表示を再構築する()
        相手.演奏.楽曲の設定の変更を反映する()
        return {
            文言: 結果.種別 === '成功' ? '読み込み完了' : '未保存: 初期楽曲を表示中',
            エラーか: false,
        }
    }

    相手.画面.インスペクター.永続化.on保存クリック(() => {
        void パネル操作を実行する(相手.画面.インスペクター.永続化, '保存中...', 保存する, '保存失敗')
    })
    相手.画面.インスペクター.永続化.on読込クリック(() => {
        void パネル操作を実行する(相手.画面.インスペクター.永続化, '読み込み中...', 読み込む, '読込失敗')
    })
}
