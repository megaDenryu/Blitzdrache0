import type { 楽曲履歴適用サービス } from './操作コマンド/楽曲履歴適用サービス.ts'
import type { 楽曲編集UI状態 } from './楽曲編集UI状態.ts'
import { 新しいパターンの既定の小節数 } from '../../生成/編集資源契約.ts'
import type { 楽曲編集状態 } from './編集モデル/index.ts'
import {
    新規パターンの名乗りを発番する,
    新規パターンの表示名を生成する,
    新規パターンの初期の進行の参照を決める,
} from './画面/パネル/パターン/パターン操作判定.ts'
import type { 演奏サービス, 楽曲編集画面 } from './画面/index.ts'

// 右サイドバーの編集パネル（パターン・曲構成・トラック設定・コード進行・ミキサー）の事象をコマンドへ配線する。
export function 楽曲編集パネル群を配線する(
    画面: 楽曲編集画面,
    状態: 楽曲編集状態,
    UI状態: 楽曲編集UI状態,
    操作: 楽曲履歴適用サービス,
    表示を再構築する: () => void,
    演奏: 演奏サービス,
): void {
    画面.インスペクター.パネル群.ミキサー.配線する({
        onミキサー設定変更: (新しいミキサー設定) => {
            操作.コマンドを実行する({ 種類: 'ミキサー設定を変える', 値: { 新しいミキサー設定 } })
            演奏.楽曲の設定の変更を反映する()
        },
    })

    画面.インスペクター.パネル群.トラック設定.配線する({
        on楽器変更: (トラックの位置, 新しい楽器) => {
            操作.コマンドを実行する({ 種類: 'トラックの楽器を変える', 値: { トラックの位置, 新しい楽器 } })
        },
        on音量変更: (トラックの位置, 新しい音量) => {
            操作.コマンドを実行する({ 種類: 'トラックの音量を変える', 値: { トラックの位置, 新しい音量 } })
            演奏.楽曲の設定の変更を反映する()
        },
        on進行割り当て変更: (トラックの位置, 新しい進行の割り当て) => {
            操作.コマンドを実行する({
                種類: 'トラックの進行の割り当てを変える',
                値: { トラックの位置, 新しい進行の割り当て },
            })
        },
    })

    画面.インスペクター.パネル群.パターン.配線する({
        onパターン選択: (名乗り) => {
            状態.選択中パターンの名乗り = 名乗り
            UI状態.選択中のカード = null
            表示を再構築する()
        },
        onパターン追加: () => {
            const 楽曲 = 状態.楽曲を取得する()
            const 名乗り = 新規パターンの名乗りを発番する(楽曲.パターン一覧)
            const 表示名 = 新規パターンの表示名を生成する(楽曲.パターン一覧)
            const 進行の参照 = 新規パターンの初期の進行の参照を決める()
            操作.コマンドを実行する({
                種類: 'パターンを追加する',
                値: { 名乗り, 表示名, 小節数: 新しいパターンの既定の小節数, 進行の参照 },
            })
            状態.選択中パターンの名乗り = 名乗り
            UI状態.選択中のカード = null
            表示を再構築する()
        },
        onパターン削除: (名乗り) => {
            操作.コマンドを実行する({ 種類: 'パターンを削除する', 値: { 名乗り } })
            状態.選択中パターンが失われていたら選び直す()
            UI状態.選択中のカード = null
            表示を再構築する()
        },
        on表示名変更: (名乗り, 新しい表示名) => {
            操作.コマンドを実行する({ 種類: 'パターンの表示名を変える', 値: { 名乗り, 新しい表示名 } })
        },
        on進行変更: (名乗り, 新しい進行の参照) => {
            操作.コマンドを実行する({ 種類: 'パターンの進行を変える', 値: { 名乗り, 新しい進行の参照 } })
        },
        on小節数変更: (名乗り, 新しい小節数) => {
            操作.コマンドを実行する({ 種類: 'パターンの小節数を変える', 値: { 名乗り, 新しい小節数 } })
            表示を再構築する()
        },
    })

    画面.インスペクター.パネル群.曲構成.配線する({
        on節変更: (節の位置, 新しいパターンの名乗り, 新しい繰り返し回数) => {
            操作.コマンドを実行する({
                種類: '曲の節を変える',
                値: { 節の位置, 新しいパターンの名乗り, 新しい繰り返し回数 },
            })
            UI状態.選択中のカードが失われていたら外す(状態.楽曲.曲構成)
            表示を再構築する()
        },
    })

    画面.インスペクター.パネル群.コード進行.配線する({
        on独自進行保存: (進行) => {
            操作.コマンドを実行する({ 種類: '独自の進行を保存する', 値: { 進行 } })
        },
        on独自進行削除: (名前) => {
            操作.コマンドを実行する({ 種類: '独自の進行を削除する', 値: { 名前 } })
        },
    })
}
