import {
    周波数ヘルツ,
    秒,
    雑音の音源,
    乱数の種,
    type I音声の作業場,
    type 音声部品,
} from 'SengenAudio'
import type { 打楽器の音色の作り方 } from '../../編集モデル/index.ts'
import type { 打楽器を鳴らす音源, 音高を鳴らす音源 } from './音源の口.ts'
import { 減算合成の音源を組み立てる } from './音高の音源を組み立てる.ts'
import { 通す帯域を濾波の種類へ写す } from './波と帯域の写し.ts'

const 打撃の雑音の種 = 乱数の種.生成する(20260830)

// 音高を持つ音源へ、打楽器の決まった周波数をいつも同じ値で渡す包み。
// 打楽器の行は音高を持たないため、周波数の指定を鳴らす側から取り除く役目を持つ。
class 決まった音高の打撃 implements 打楽器を鳴らす音源 {
    public constructor(
        private readonly _音源: 音高を鳴らす音源,
        private readonly _周波数: 周波数ヘルツ,
    ) {}

    public 鳴らす(引数: { 開始時刻: 秒; 長さ: 秒; 出力先: 音声部品 }): void {
        this._音源.鳴らす({ ...引数, 周波数: this._周波数 })
    }

    public 破棄する(): void {
        this._音源.破棄する()
    }
}

// 打楽器1つ分の音色の作り方から、その打撃を鳴らす音源を組み立てる。
export function 打楽器の音源を組み立てる(
    作業場: I音声の作業場,
    作り方: 打楽器の音色の作り方,
): 打楽器を鳴らす音源 {
    switch (作り方.種類) {
        case '雑音の打撃':
            return new 雑音の音源({
                作業場,
                種: 打撃の雑音の種,
                帯域の濾波: {
                    種類: 通す帯域を濾波の種類へ写す(作り方.通す帯域),
                    中心の周波数: 周波数ヘルツ.生成する(作り方.中心の周波数),
                    鋭さ: 作り方.鋭さ,
                },
                減衰の秒数: 秒.生成する(作り方.減衰の秒数),
            })
        case '決まった音高の打撃':
            return new 決まった音高の打撃(
                減算合成の音源を組み立てる(作業場, 作り方.作り方),
                周波数ヘルツ.生成する(作り方.周波数ヘルツ),
            )
    }
}

// 打楽器は打点の長さに関わらず、音色が決めた短い時間だけ鳴る。その時間をこの工程が答える。
export function 打楽器の打撃の長さ(作り方: 打楽器の音色の作り方): 秒 {
    return 秒.生成する(作り方.長さの秒数)
}
