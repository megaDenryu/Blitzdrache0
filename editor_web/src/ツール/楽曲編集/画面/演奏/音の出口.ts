import {
    音量の比,
    合流点を作る,
    全体の音量を作る,
    動的圧縮を作る,
    残響を作る,
    遅延を作る,
    秒,
    音声の出力先を作る,
    type I音声の作業場,
    type 合流点,
    type 全体の音量,
    type 音声の出力先,
    type 遅延,
} from 'SengenAudio'
import type { ミキサー設定, 楽曲 } from '../../../../生成/編集資源契約.ts'
import { ステップ, type テンポ } from '../../編集モデル/index.ts'
import {
    圧縮の折れ曲がりの幅,
    圧縮を始める音量,
    圧縮比,
    残響の減衰の指数,
    残響の長さ,
    残響の雑音の種,
    遅延の帰還の比,
    遅延の緩衝の最大の長さ,
} from './音の出口の効果の値.ts'

// 全トラックの音が合流してから出口へ出るまでの効果の木を所有する。
// トラックごとの合流点は主経路のほか、残響と遅延へも同じ信号を送る。
// 範囲の外の比が来たら音量の比が例外を投げる。ここで既定値へ丸めると、壊れた楽曲が黙って鳴ってしまう。
export class 音の出口 {
    private readonly _出力先: 音声の出力先
    private readonly _全体の音量: 全体の音量
    private readonly _残響の戻り: 全体の音量
    private readonly _遅延の戻り: 全体の音量
    private readonly _遅延: 遅延
    private readonly _トラックの合流点一覧: readonly 合流点[]

    public constructor(作業場: I音声の作業場, 楽曲: 楽曲) {
        const 設定 = 楽曲.ミキサー設定
        this._出力先 = 音声の出力先を作る({ 作業場 })
        this._全体の音量 = 全体の音量を作る({ 作業場, 初期音量: 音量の比.生成する(設定.全体の音量) })
        this._残響の戻り = 全体の音量を作る({ 作業場, 初期音量: 音量の比.生成する(設定.残響の量) })
        this._遅延の戻り = 全体の音量を作る({ 作業場, 初期音量: 音量の比.生成する(設定.遅延の量) })
        const 残響本体 = 残響を作る({
            作業場,
            長さ: 残響の長さ,
            減衰の指数: 残響の減衰の指数,
            種: 残響の雑音の種,
        })
        this._遅延 = 遅延を作る({
            作業場,
            遅延の長さ: 秒.生成する(0),
            帰還の比: 遅延の帰還の比,
            最大の遅延: 遅延の緩衝の最大の長さ,
        })
        this._トラックの合流点一覧 = 楽曲.トラック構成.map((トラック) =>
            合流点を作る({ 作業場, 初期音量: 音量の比.生成する(トラック.音量) }),
        )

        this._出力先.child(
            動的圧縮を作る({ 作業場, 圧縮を始める音量, 圧縮の折れ曲がりの幅, 圧縮比 }).child(
                this._全体の音量.childs([
                    ...this._トラックの合流点一覧,
                    this._残響の戻り.child(残響本体),
                    this._遅延の戻り.child(this._遅延),
                ]),
            ),
        )
        for (const 合流点 of this._トラックの合流点一覧) {
            合流点.送り先を足す(残響本体, 音量の比.最大())
            合流点.送り先を足す(this._遅延, 音量の比.最大())
        }
    }

    public トラックの合流点(トラックの位置: number): 合流点 {
        const 合流点 = this._トラックの合流点一覧[トラックの位置]
        if (合流点 === undefined) {
            throw new Error(`音の出口が持たないトラックへ出そうとしています: トラックの位置=${トラックの位置}`)
        }
        return 合流点
    }

    public トラックの本数(): number {
        return this._トラックの合流点一覧.length
    }

    public ミキサー設定を反映する(設定: ミキサー設定, 現在のテンポ: テンポ): void {
        this._全体の音量.音量を設定する(音量の比.生成する(設定.全体の音量))
        this._残響の戻り.音量を設定する(音量の比.生成する(設定.残響の量))
        this._遅延の戻り.音量を設定する(音量の比.生成する(設定.遅延の量))
        const 長さ = 現在のテンポ.ステップ数の秒数(ステップ.生成する(設定.遅延のステップ数))
        this._遅延.遅延の長さを設定する(秒.生成する(長さ.数値()))
    }

    public トラックの音量を反映する(トラックの位置: number, 音量: number): void {
        this.トラックの合流点(トラックの位置).音量を設定する(音量の比.生成する(音量))
    }

    public 破棄する(): void {
        this._出力先.破棄する()
    }
}
