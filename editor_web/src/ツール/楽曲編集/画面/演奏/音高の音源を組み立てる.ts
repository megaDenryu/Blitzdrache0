import {
    加算合成の音源,
    周波数ヘルツ,
    周波数変調合成の音源,
    撥弦合成の音源,
    減算合成の音源,
    乱数の種,
    秒,
    音量の比,
    type I音声の作業場,
} from 'SengenAudio'
import type { 減算合成の作り方, 音色の作り方 } from '../../編集モデル/index.ts'
import type { 音高を鳴らす音源 } from './音源の口.ts'
import { 波の形を発振の波形へ写す } from './波と帯域の写し.ts'

// 試作は Math.random で撥弦の励起を作るが、同じ楽曲が同じ音を出すことを確かめられるよう種つきの乱数へ置き換える。
const 撥弦の励起の種 = 乱数の種.生成する(20260829)

// 減算合成は打楽器の決まった音高の打撃からも組むため、単独で呼べる工程として切り出している。
export function 減算合成の音源を組み立てる(
    作業場: I音声の作業場,
    作り方: 減算合成の作り方,
): 減算合成の音源 {
    return new 減算合成の音源({
        作業場,
        波形: 波の形を発振の波形へ写す(作り方.波の形),
        濾波の包絡: {
            始まりの遮断周波数: 周波数ヘルツ.生成する(作り方.濾波の始まりの遮断周波数),
            終わりの遮断周波数: 周波数ヘルツ.生成する(作り方.濾波の終わりの遮断周波数),
        },
        音量の包絡: {
            立ち上がりの秒数: 秒.生成する(作り方.立ち上がりの秒数),
            保持の秒数: 秒.生成する(作り方.保持の秒数),
            減衰の秒数: 秒.生成する(作り方.減衰の秒数),
        },
    })
}

// 音色の作り方から、その技法の音源を1つ組み立てる。技法の網羅は型が保証する。
export function 音高の音源を組み立てる(
    作業場: I音声の作業場,
    作り方: 音色の作り方,
): 音高を鳴らす音源 {
    switch (作り方.種類) {
        case '加算合成':
            return new 加算合成の音源({
                作業場,
                倍音一覧: 作り方.倍音一覧.map((倍音) => ({
                    比: 倍音.比,
                    利得: 音量の比.生成する(倍音.利得),
                    減衰の秒数: 秒.生成する(倍音.音を止めるまでの秒数),
                })),
            })
        case '減算合成':
            return 減算合成の音源を組み立てる(作業場, 作り方)
        case '撥弦合成':
            return new 撥弦合成の音源({
                作業場,
                減衰の強さ: 作り方.減衰の強さ,
                胴の濾波: {
                    開始遮断周波数: 周波数ヘルツ.生成する(作り方.胴の濾波の開始遮断周波数),
                    終了遮断周波数: 周波数ヘルツ.生成する(作り方.胴の濾波の終了遮断周波数),
                },
                種: 撥弦の励起の種,
            })
        case '周波数変調合成':
            return new 周波数変調合成の音源({
                作業場,
                変調波の周波数比: 作り方.変調波の周波数比,
                変調の深さ: 作り方.変調の深さ,
                深さの減衰の秒数: 秒.生成する(作り方.深さの減衰の秒数),
            })
    }
}
