import {
    ステップ,
    パターンのステップで鳴り始める音一覧を求める,
    テンポ,
    演奏に使う曲構成,
    演奏の時刻表,
    秒数,
    曲のステップ位置を解決する,
    type 演奏の範囲,
    type 楽曲編集状態,
} from '../../編集モデル/index.ts'
import { 発音コマンドを組み立てる } from './発音コマンド.ts'
import type { 再生位置 } from './再生位置.ts'
import type { 音声の場 } from './音声の場.ts'

// この先どこまでの音を音声の時計へ預けておくか。打点の無いステップも数え進めるため、件数ではなく時間の幅で決める。
const 先まで予約する幅 = 秒数.生成する(1.0)

// 速さを変えたときに、予約をやり直す起点を現在より少しだけ先へ置く余裕。
const 予約をやり直す余裕 = 秒数.生成する(0.06)

// 1回の再生の進み具合を持つ。演奏を始めるたびに作り直し、止めたら捨てる。
export class 演奏の進行 {
    private readonly _時刻表: 演奏の時刻表
    private _次に予約する通しステップ: ステップ = ステップ.ゼロ()

    public constructor(
        private readonly _場: 音声の場,
        private readonly _状態: 楽曲編集状態,
        private _範囲: 演奏の範囲,
        始まりの時刻: 秒数,
    ) {
        this._時刻表 = new 演奏の時刻表({
            基準の時刻: 始まりの時刻,
            基準の通しステップ: ステップ.ゼロ(),
            テンポ: テンポ.生成する(_状態.楽曲.テンポ),
        })
    }

    public 範囲を変える(範囲: 演奏の範囲): void {
        this._範囲 = 範囲
    }

    public 補充する(): void {
        const 限界の時刻 = this._場.現在時刻().足す(先まで予約する幅)
        while (!限界の時刻.より前か(this._時刻表.通しステップの時刻(this._次に予約する通しステップ))) {
            this._次の1ステップを預ける()
        }
    }

    public 現在の再生位置(): 再生位置 | null {
        return this._通しステップの再生位置(this._時刻表.時刻の通しステップ(this._場.現在時刻()))
    }

    // 速さが変わったら、まだ音になっていない予約を捨てて、いまの位置から新しい速さで組み直す。
    public 速さの変化を取り込む(): void {
        const 新しいテンポ = テンポ.生成する(this._状態.楽曲.テンポ)
        if (新しいテンポ.同じか(this._時刻表.現在のテンポ)) return
        const いまの通しステップ = this._時刻表.時刻の通しステップ(this._場.現在時刻())
        const 起点の時刻 = this._場.現在時刻().足す(予約をやり直す余裕)
        this._場.予定表.やめる()
        this._時刻表.基準を置き直す({
            基準の時刻: 起点の時刻,
            基準の通しステップ: いまの通しステップ.次(),
            テンポ: 新しいテンポ,
        })
        this._次に予約する通しステップ = いまの通しステップ.次()
        this._場.予定表.始める()
    }

    public 現在のテンポ(): テンポ {
        return this._時刻表.現在のテンポ
    }

    private _次の1ステップを預ける(): void {
        const 通しステップ = this._次に予約する通しステップ
        this._次に予約する通しステップ = 通しステップ.次()
        const 時刻 = this._時刻表.通しステップの時刻(通しステップ)
        // 見張りが大きく遅れたときは既に過ぎた時刻になる。過ぎた音は預けられないため数え進めるだけにする。
        if (時刻.より前か(this._場.現在時刻())) return
        // 拍は打点の有無と関わりなく鳴るため、パターンを解決する前に預ける。
        this._場.メトロノームの音.拍の頭なら予約する(通しステップ, this._場.音声の時計の秒へ写す(時刻))
        const 位置 = this._通しステップの再生位置(通しステップ)
        if (位置 === null) return
        const 対象のパターン = this._状態.楽曲.パターン一覧.find((p) => p.名乗り === 位置.パターンの名乗り)
        if (対象のパターン === undefined) return
        const 音一覧 = パターンのステップで鳴り始める音一覧を求める(
            this._状態.楽曲,
            対象のパターン,
            位置.パターン内ステップ,
        )
        for (const 音 of 音一覧) {
            this._場.予定表.予約する({
                開始時刻: this._場.音声の時計の秒へ写す(時刻),
                コマンド: 発音コマンドを組み立てる(音, this._時刻表.現在のテンポ, this._場.音源棚, this._場.出口),
            })
        }
    }

    private _通しステップの再生位置(通しステップ: ステップ): 再生位置 | null {
        const 開いているパターンの名乗り = this._状態.選択中パターンの名乗り
        if (開いているパターンの名乗り === null) return null
        const 位置 = 曲のステップ位置を解決する(
            演奏に使う曲構成(this._範囲, this._状態.楽曲),
            this._状態.楽曲.パターン一覧,
            通しステップ.数値(),
            開いているパターンの名乗り,
        )
        return { ...位置, 通しステップ: 通しステップ.数値() }
    }
}
