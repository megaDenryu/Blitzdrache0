import type { 打楽器の音色の作り方 } from '../../編集モデル/index.ts'

// メトロノームの2種の音。曲の楽器と混ざっても拍が聞き分けられるよう、倍音を持たない正弦波の短い音にする。
// 打楽器と同じ作り方の型で書けるのは、拍の1打が音高を持たない短い打撃だからである。

// 小節の頭に鳴らす音。
const 小節の頭の周波数ヘルツ = 1600

// 小節の中の拍に鳴らす音。小節の頭のちょうど1オクターブ下(半分の周波数)にして、2つが同じ音色に聞こえるようにする。
const 小節の中の拍の周波数ヘルツ = 800

function 拍の音色を組み立てる(周波数ヘルツ: number): 打楽器の音色の作り方 {
    return {
        種類: '決まった音高の打撃',
        周波数ヘルツ,
        長さの秒数: 0.008,
        作り方: {
            種類: '減算合成',
            波の形: '正弦',
            濾波の始まりの遮断周波数: 18000,
            濾波の終わりの遮断周波数: 18000,
            立ち上がりの秒数: 0.001,
            保持の秒数: 0.0,
            減衰の秒数: 0.04,
        },
    }
}

export const 小節の頭の音色: 打楽器の音色の作り方 = 拍の音色を組み立てる(小節の頭の周波数ヘルツ)
export const 小節の中の拍の音色: 打楽器の音色の作り方 = 拍の音色を組み立てる(小節の中の拍の周波数ヘルツ)

// メトロノームの音量。曲と一緒に鳴らしても拍が聞き取れ、かつ曲より前に出ない大きさにする。
export const メトロノームの音量 = 0.3
