import type { 周波数ヘルツ, 秒, 音声部品 } from 'SengenAudio'

// SengenAudioの音高を持つ4種の音源(加算合成・減算合成・撥弦合成・周波数変調合成)が共通して持つ発音の口。
// 楽器の側は技法の違いを知らずに鳴らせる。
export interface 音高を鳴らす音源 {
    鳴らす(引数: { 開始時刻: 秒; 周波数: 周波数ヘルツ; 長さ: 秒; 出力先: 音声部品 }): void
    破棄する(): void
}

// 打楽器の1打分を鳴らす口。音高を取らないため、鳴らす側は行の位置だけを知っていればよい。
export interface 打楽器を鳴らす音源 {
    鳴らす(引数: { 開始時刻: 秒; 長さ: 秒; 出力先: 音声部品 }): void
    破棄する(): void
}
