// 音を鳴らそうとして起きた、人へ伝えないと分からないことがら。
// 押したのに何も起きなかったように見える状態を作らないため、失敗は必ずこの形で画面まで運ぶ。
export interface 演奏の知らせ {
    readonly 種類: '音を出せなかった'
    readonly 文言: string
    readonly 詳しい原因: string
}

// 演奏の知らせを受け取る側の規約。伝えることが無くなったときは知らせなし(null)が届く。
export interface I演奏の知らせの届け先 {
    演奏の知らせが届いた(知らせ: 演奏の知らせ | null): void
}

// ブラウザは人の操作を起点にしないと音を出さず、その判断が下りなかったときに音声の場を開けない。
// 利用者にできることは「もう一度押す」ことだけなので、そう書く。
const 音を出せなかったときの文言 = 'ブラウザが音を止めています。もう一度、再生を押してください。'

export function 音を出せなかった知らせを組み立てる(原因: unknown): 演奏の知らせ {
    return {
        種類: '音を出せなかった',
        文言: 音を出せなかったときの文言,
        詳しい原因: 原因 instanceof Error ? 原因.message : String(原因),
    }
}
