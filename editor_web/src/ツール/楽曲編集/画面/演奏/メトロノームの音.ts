import {
    全体の音量を作る,
    音声の出力先を作る,
    音量の比,
    type I音声の作業場,
    type 全体の音量,
    type 演奏予定表,
    type 秒,
    type 音声の出力先,
} from 'SengenAudio'
import {
    通しステップの拍の位置づけを求める,
    type ステップ,
    type メトロノームの入切,
    type 打楽器の音色の作り方,
    type 拍の頭の種類,
} from '../../編集モデル/index.ts'
import { 打楽器の打撃の長さ, 打楽器の音源を組み立てる } from './打楽器の音源を組み立てる.ts'
import { メトロノームの音量, 小節の中の拍の音色, 小節の頭の音色 } from './メトロノームの音色.ts'
import { 拍を刻むコマンド } from './拍を刻むコマンド.ts'
import type { 打楽器の打撃 } from './楽器の音源棚.ts'

// メトロノームの2種の音と、その音だけが通る出口を所有する。演奏の進行から通しステップと時刻を受け、拍の頭なら予定表へ預ける。
// 注意: 曲の音とは別に音声の出力先をもう1つ持つ。曲のミキサー・残響・遅延・圧縮のどれも通さないためである。
// 曲の音量を絞ったときや曲が大きく鳴ったときに拍の聞こえ方が変わると、拍を数える道具として使えない。
// 音声の出力先は作業場の同じ出力ノードを包むだけであり、破棄が切るのはそのノードから出る接続(存在しない)であるため、
// 2つ持っても互いの音を止めない。
export class メトロノームの音 {
    private readonly _出口: 音声の出力先
    private readonly _音量: 全体の音量
    private readonly _小節の頭の打撃: 打楽器の打撃
    private readonly _小節の中の拍の打撃: 打楽器の打撃

    public constructor(
        作業場: I音声の作業場,
        private readonly _予定表: 演奏予定表,
        private readonly _入切: メトロノームの入切,
    ) {
        this._出口 = 音声の出力先を作る({ 作業場 })
        this._音量 = 全体の音量を作る({ 作業場, 初期音量: 音量の比.生成する(メトロノームの音量) })
        this._出口.child(this._音量)
        this._小節の頭の打撃 = 拍の打撃を組み立てる(作業場, 小節の頭の音色)
        this._小節の中の拍の打撃 = 拍の打撃を組み立てる(作業場, 小節の中の拍の音色)
    }

    // 拍の頭でない通しステップでは何もしない。メトロノームは打点の有無と関わりなく拍の枠だけで鳴るためである。
    public 拍の頭なら予約する(通しステップ: ステップ, 開始時刻: 秒): void {
        const 位置づけ = 通しステップの拍の位置づけを求める(通しステップ)
        if (位置づけ === '拍の頭でない') return
        const 打撃 = this._拍の頭の種類の打撃(位置づけ)
        this._予定表.予約する({
            開始時刻,
            コマンド: new 拍を刻むコマンド(this._入切, 打撃.音源, 打撃.長さ, this._音量),
        })
    }

    public 破棄する(): void {
        this._小節の頭の打撃.音源.破棄する()
        this._小節の中の拍の打撃.音源.破棄する()
        this._出口.破棄する()
    }

    private _拍の頭の種類の打撃(種類: 拍の頭の種類): 打楽器の打撃 {
        return 種類 === '小節の頭' ? this._小節の頭の打撃 : this._小節の中の拍の打撃
    }
}

// 音色1つから、拍の1打を鳴らす音源とその長さを組み立てる。組み立ての工程であり、作業場が要るのは構築のときだけである。
function 拍の打撃を組み立てる(作業場: I音声の作業場, 音色: 打楽器の音色の作り方): 打楽器の打撃 {
    return { 音源: 打楽器の音源を組み立てる(作業場, 音色), 長さ: 打楽器の打撃の長さ(音色) }
}
