import type { 楽曲編集コマンド } from '../../../生成/編集資源契約.ts'
import type { 升目の当たりの記録 } from './打ち込み見込み.ts'
import { ドラッグ見込みを導出する } from './ドラッグ見込み導出.ts'

// 離したときの起点と現在の当たり位置から、確定コマンドを生成する。
export function 確定コマンドを生成する(
    起点: 升目の当たりの記録,
    現在: 升目の当たりの記録,
    ボタン: number,
    進行に従うか: boolean,
): 楽曲編集コマンド {
    const 見込み = ドラッグ見込みを導出する(起点, 現在, ボタン, 進行に従うか)
    switch (見込み.種類) {
        case '音を伸ばす':
            return { 種類: '音を伸ばす', 値: { ...見込み } }
        case '打点を置く':
            return { 種類: '打点を置く', 値: { ...見込み } }
        case '範囲の打点を消す':
            return { 種類: '範囲の打点を消す', 値: { ...見込み } }
        case '打点を消す':
            return { 種類: '打点を消す', 値: { ...見込み } }
    }
}
