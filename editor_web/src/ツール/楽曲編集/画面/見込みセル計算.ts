import type { セル } from '../編集モデル/index.ts'
import type { 打ち込みドラッグ見込み } from './打ち込み見込み.ts'

// ドラッグ見込みを反映したセルを計算する。
export function 見込みを反映したセルを計算する(
    元のセル: セル,
    パターンの名乗り: string,
    トラックの位置: number,
    行位置: number,
    ステップ: number,
    見込み: 打ち込みドラッグ見込み | null,
): セル {
    if (見込み === null) return 元のセル
    if (見込み.対象.パターンの名乗り !== パターンの名乗り
        || 見込み.対象.トラックの位置 !== トラックの位置
        || 見込み.対象.行の位置 !== 行位置) {
        return 元のセル
    }

    switch (見込み.種類) {
        case '打点を置く':
            return ステップ === 見込み.ステップ
                ? { 種類: '音の始まり', 進行に従うか: 見込み.進行に従うか }
                : 元のセル
        case '打点を消す':
            return ステップ === 見込み.ステップ ? { 種類: '打点なし' } : 元のセル
        case '音を伸ばす': {
            const 開始 = Math.min(見込み.始まりのステップ, 見込み.終わりのステップ)
            const 終了 = Math.max(見込み.始まりのステップ, 見込み.終わりのステップ)
            if (ステップ < 開始 || ステップ > 終了) return 元のセル
            return {
                種類: ステップ === 開始 ? '音の始まり' : '音の継続',
                進行に従うか: 見込み.進行に従うか,
            }
        }
        case '範囲の打点を消す': {
            const 開始 = Math.min(見込み.始まりのステップ, 見込み.終わりのステップ)
            const 終了 = Math.max(見込み.始まりのステップ, 見込み.終わりのステップ)
            if (ステップ < 開始 || ステップ > 終了) return 元のセル
            return { 種類: '打点なし' }
        }
    }
}
