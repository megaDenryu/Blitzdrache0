import type { トラックの種類, トラック定義, 楽器, 音の並び } from '../../../../../生成/編集資源契約.ts'
import { 音の並びへ割り当てられる楽器一覧を求める } from '../../../編集モデル/index.ts'

// トラックの種類は選べる楽器を絞る根拠ではなく、選択肢の並び順を決める根拠としてだけ残す(判断17)。
const 旋律系楽器一覧: readonly 楽器[] = ['グランドピアノ', '弦楽合奏', 'フルート', '矩形波の主旋律']
const 伴奏系楽器一覧: readonly 楽器[] = ['アコースティックギター', 'グランドピアノ', 'エレクトリックピアノ']
const 低音系楽器一覧: readonly 楽器[] = ['ウッドベース', 'エレキベース', '三角波のベース']
const 打楽器系楽器一覧: readonly 楽器[] = ['生ドラム', '矩形波と雑音のドラム']

function トラックの種類に対応する優先楽器一覧を取得する(種類: トラックの種類): readonly 楽器[] {
    switch (種類) {
        case '旋律':
            return 旋律系楽器一覧
        case '伴奏':
            return 伴奏系楽器一覧
        case '低音':
            return 低音系楽器一覧
        case '打楽器':
            return 打楽器系楽器一覧
    }
}

// トラックへ割り当てられる楽器を、トラックの種類に合う楽器が先に来る順に並べる。
// 選べる楽器はトラックの音の並びの種類だけが決め、トラックの種類は並び順だけを決める。
export function トラックが選べる楽器をトラックの種類の順に並べる(トラック: トラック定義): readonly 楽器[] {
    const 候補一覧 = 音の並びへ割り当てられる楽器一覧を求める(トラック.音の並び.種類)
    const 優先一覧 = トラックの種類に対応する優先楽器一覧を取得する(トラック.種類).filter((楽器名) =>
        候補一覧.includes(楽器名),
    )
    const 残り一覧 = 候補一覧.filter((楽器名) => !優先一覧.includes(楽器名))
    return [...優先一覧, ...残り一覧]
}

// トラックの音の並びの種類に対して指定された楽器が割り当て可能かを判定する。
export function トラックの楽器は妥当か(音の並びの種類: 音の並び['種類'], 割り当てた楽器: 楽器): boolean {
    return 音の並びへ割り当てられる楽器一覧を求める(音の並びの種類).includes(割り当てた楽器)
}
