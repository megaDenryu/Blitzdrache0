import type { トラックの種類, 楽器 } from '../../../../../生成/編集資源契約.ts'

// トラックの種類ごとに割り当て可能な楽器一覧。サーバーの型契約と一致させる。
const 旋律トラックの楽器一覧: readonly 楽器[] = [
    'グランドピアノ',
    '弦楽合奏',
    'フルート',
    '矩形波の主旋律',
]

const 伴奏トラックの楽器一覧: readonly 楽器[] = [
    'アコースティックギター',
    'グランドピアノ',
    'エレクトリックピアノ',
]

const 低音トラックの楽器一覧: readonly 楽器[] = [
    'ウッドベース',
    'エレキベース',
    '三角波のベース',
]

const 打楽器トラックの楽器一覧: readonly 楽器[] = [
    '生ドラム',
    '矩形波と雑音のドラム',
]

// 指定されたトラックの種類で選択可能な楽器の一覧を返す。
export function トラックの種類から選べる楽器一覧を取得する(種類: トラックの種類): readonly 楽器[] {
    switch (種類) {
        case '旋律':
            return 旋律トラックの楽器一覧
        case '伴奏':
            return 伴奏トラックの楽器一覧
        case '低音':
            return 低音トラックの楽器一覧
        case '打楽器':
            return 打楽器トラックの楽器一覧
    }
}

// トラックの種類に対して指定された楽器が割り当て可能かを判定する。
export function トラックの楽器は妥当か(種類: トラックの種類, 割り当てた楽器: 楽器): boolean {
    const 候補一覧 = トラックの種類から選べる楽器一覧を取得する(種類)
    return 候補一覧.includes(割り当てた楽器)
}
