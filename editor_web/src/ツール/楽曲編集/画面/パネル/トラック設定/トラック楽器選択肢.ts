// 参照: 正本はRustの`楽器::音の種類を得る`(crates/editor_server/src/resource/music/instrument.rs)であり、この switch は網羅検査で追随を強制する。
import type { トラックの種類, 楽器, 音の並び } from '../../../../../生成/編集資源契約.ts'

type 音の並びの種類 = 音の並び['種類']
type 楽器の音の種類 = '音高の楽器' | '打楽器の楽器'

// 楽器が音高の楽器か打楽器の楽器かの判別はここ1箇所に置く。
function 楽器の音の種類を判定する(対象: 楽器): 楽器の音の種類 {
    switch (対象) {
        case '生ドラム':
        case '矩形波と雑音のドラム':
            return '打楽器の楽器'
        case 'グランドピアノ':
        case '弦楽合奏':
        case 'フルート':
        case '矩形波の主旋律':
        case 'アコースティックギター':
        case 'エレクトリックピアノ':
        case 'ウッドベース':
        case 'エレキベース':
        case '三角波のベース':
            return '音高の楽器'
        default: {
            const 漏れ: never = 対象
            return 漏れ
        }
    }
}

const 全楽器一覧: readonly 楽器[] = [
    'グランドピアノ',
    '弦楽合奏',
    'フルート',
    '矩形波の主旋律',
    'アコースティックギター',
    'エレクトリックピアノ',
    'ウッドベース',
    'エレキベース',
    '三角波のベース',
    '生ドラム',
    '矩形波と雑音のドラム',
]

// 音の並びの種類が受け入れる楽器の音の種類と一致する楽器だけを、判別済みの一覧から絞り込む。
function 音の並びの種類に対応する楽器一覧を取得する(音の並びの種類: 音の並びの種類): readonly 楽器[] {
    switch (音の並びの種類) {
        case '音高の行一覧':
            return 全楽器一覧.filter((楽器名) => 楽器の音の種類を判定する(楽器名) === '音高の楽器')
        case '打楽器の行一覧':
            return 全楽器一覧.filter((楽器名) => 楽器の音の種類を判定する(楽器名) === '打楽器の楽器')
    }
}

// トラックの種類は選べる楽器を絞る根拠ではなく、選択肢の並び順を決める根拠としてだけ残す。
const 旋律系楽器一覧: readonly 楽器[] = ['グランドピアノ', '弦楽合奏', 'フルート', '矩形波の主旋律']
const 伴奏系楽器一覧: readonly 楽器[] = ['アコースティックギター', 'グランドピアノ', 'エレクトリックピアノ']
const 低音系楽器一覧: readonly 楽器[] = ['ウッドベース', 'エレキベース', '三角波のベース']
const 打楽器系楽器一覧: readonly 楽器[] = ['生ドラム', '矩形波と雑音のドラム']

function トラックの種類に対応する優先楽器一覧を取得する(種類: トラックの種類): readonly 楽器[] {
    switch (種類) {
        case '旋律':
            return 旋律系楽器一覧
        case '伴奏':
            return 伴奏系楽器一覧
        case '低音':
            return 低音系楽器一覧
        case '打楽器':
            return 打楽器系楽器一覧
    }
}

// 音の並びの種類が選べる楽器を決め、トラックの種類は先に出す順序だけを決める。
export function 音の並びの種類から選べる楽器一覧を取得する(
    音の並びの種類: 音の並びの種類,
    トラックの種類: トラックの種類,
): readonly 楽器[] {
    const 候補一覧 = 音の並びの種類に対応する楽器一覧を取得する(音の並びの種類)
    const 優先一覧 = トラックの種類に対応する優先楽器一覧を取得する(トラックの種類).filter((楽器名) =>
        候補一覧.includes(楽器名),
    )
    const 残り一覧 = 候補一覧.filter((楽器名) => !優先一覧.includes(楽器名))
    return [...優先一覧, ...残り一覧]
}

// トラックの音の並びの種類に対して指定された楽器が割り当て可能かを判定する。
export function トラックの楽器は妥当か(音の並びの種類: 音の並びの種類, 割り当てた楽器: 楽器): boolean {
    return 音の並びの種類に対応する楽器一覧を取得する(音の並びの種類).includes(割り当てた楽器)
}
