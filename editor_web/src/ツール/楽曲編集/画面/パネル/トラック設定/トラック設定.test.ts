import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import {
    トラックの種類から選べる楽器一覧を取得する,
    トラックの楽器は妥当か,
} from './トラック楽器選択肢.ts'

describe('トラック楽器選択肢のテスト', () => {
    it('旋律トラックで選べる楽器が正しく絞られること', () => {
        const 楽器一覧 = トラックの種類から選べる楽器一覧を取得する('旋律')
        assert.deepEqual(楽器一覧, ['グランドピアノ', '弦楽合奏', 'フルート', '矩形波の主旋律'])
        assert.equal(トラックの楽器は妥当か('旋律', 'グランドピアノ'), true)
        assert.equal(トラックの楽器は妥当か('旋律', '生ドラム'), false)
    })

    it('伴奏トラックで選べる楽器が正しく絞られること', () => {
        const 楽器一覧 = トラックの種類から選べる楽器一覧を取得する('伴奏')
        assert.deepEqual(楽器一覧, ['アコースティックギター', 'グランドピアノ', 'エレクトリックピアノ'])
        assert.equal(トラックの楽器は妥当か('伴奏', 'アコースティックギター'), true)
        assert.equal(トラックの楽器は妥当か('伴奏', 'ウッドベース'), false)
    })

    it('低音トラックで選べる楽器が正しく絞られること', () => {
        const 楽器一覧 = トラックの種類から選べる楽器一覧を取得する('低音')
        assert.deepEqual(楽器一覧, ['ウッドベース', 'エレキベース', '三角波のベース'])
        assert.equal(トラックの楽器は妥当か('低音', 'ウッドベース'), true)
        assert.equal(トラックの楽器は妥当か('低音', 'フルート'), false)
    })

    it('打楽器トラックで選べる楽器が正しく絞られること', () => {
        const 楽器一覧 = トラックの種類から選べる楽器一覧を取得する('打楽器')
        assert.deepEqual(楽器一覧, ['生ドラム', '矩形波と雑音のドラム'])
        assert.equal(トラックの楽器は妥当か('打楽器', '生ドラム'), true)
        assert.equal(トラックの楽器は妥当か('打楽器', 'グランドピアノ'), false)
    })
})
