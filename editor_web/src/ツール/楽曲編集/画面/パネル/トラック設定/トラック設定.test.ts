import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import type { トラックの種類, トラック定義, 音の並び } from '../../../../../生成/編集資源契約.ts'
import { トラックが選べる楽器をトラックの種類の順に並べる, トラックの楽器は妥当か } from './トラック楽器選択肢.ts'

// 選べる楽器の判定が見るトラックの種類と音の並びだけを変えたトラックを作る。
function トラックを作る(種類: トラックの種類, 音の並び: 音の並び): トラック定義 {
    return { 表示名: 種類, 種類, 音の並び, 楽器: 'グランドピアノ', 音量: 0.8, 進行の割り当て: null }
}

const 音高の行: 音の並び = { 種類: '音高の行一覧', 値: [60, 62, 64] }
const 打楽器の行: 音の並び = { 種類: '打楽器の行一覧', 値: ['ハイハット', 'スネア', 'バスドラム'] }

describe('トラック楽器選択肢のテスト', () => {
    it('音高の行一覧では音高の楽器9つが選べ、旋律系が先に並ぶこと', () => {
        const 楽器一覧 = トラックが選べる楽器をトラックの種類の順に並べる(トラックを作る('旋律', 音高の行))
        assert.deepEqual(楽器一覧, [
            'グランドピアノ',
            '弦楽合奏',
            'フルート',
            '矩形波の主旋律',
            'アコースティックギター',
            'エレクトリックピアノ',
            'ウッドベース',
            'エレキベース',
            '三角波のベース',
        ])
        assert.equal(トラックの楽器は妥当か('音高の行一覧', 'グランドピアノ'), true)
        assert.equal(トラックの楽器は妥当か('音高の行一覧', '生ドラム'), false)
    })

    it('音高の行一覧で伴奏を選ぶと弦楽合奏も選べ、伴奏系が先に並ぶこと', () => {
        const 楽器一覧 = トラックが選べる楽器をトラックの種類の順に並べる(トラックを作る('伴奏', 音高の行))
        assert.deepEqual(楽器一覧, [
            'アコースティックギター',
            'グランドピアノ',
            'エレクトリックピアノ',
            '弦楽合奏',
            'フルート',
            '矩形波の主旋律',
            'ウッドベース',
            'エレキベース',
            '三角波のベース',
        ])
        assert.equal(トラックの楽器は妥当か('音高の行一覧', '弦楽合奏'), true)
    })

    it('音高の行一覧で低音を選ぶと低音系が先に並ぶこと', () => {
        const 楽器一覧 = トラックが選べる楽器をトラックの種類の順に並べる(トラックを作る('低音', 音高の行))
        assert.deepEqual(楽器一覧, [
            'ウッドベース',
            'エレキベース',
            '三角波のベース',
            'グランドピアノ',
            '弦楽合奏',
            'フルート',
            '矩形波の主旋律',
            'アコースティックギター',
            'エレクトリックピアノ',
        ])
        assert.equal(トラックの楽器は妥当か('音高の行一覧', 'ウッドベース'), true)
        assert.equal(トラックの楽器は妥当か('音高の行一覧', 'フルート'), true)
    })

    it('打楽器の行一覧では打楽器の楽器2つだけが選べ、音高の楽器は選べないこと', () => {
        const 楽器一覧 = トラックが選べる楽器をトラックの種類の順に並べる(トラックを作る('打楽器', 打楽器の行))
        assert.deepEqual(楽器一覧, ['生ドラム', '矩形波と雑音のドラム'])
        assert.equal(トラックの楽器は妥当か('打楽器の行一覧', '生ドラム'), true)
        assert.equal(トラックの楽器は妥当か('打楽器の行一覧', 'グランドピアノ'), false)
    })
})
