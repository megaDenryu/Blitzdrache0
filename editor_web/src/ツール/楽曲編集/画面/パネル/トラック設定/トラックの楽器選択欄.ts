import { SelectC } from 'sengen-ui'
import type { トラック定義, 楽器 } from '../../../../../生成/編集資源契約.ts'
import { 選択セレクト } from '../共通/スタイル.css.ts'
import { 音の並びの種類から選べる楽器一覧を取得する, トラックの楽器は妥当か } from './トラック楽器選択肢.ts'

// トラックの楽器を選ぶ欄。選べる楽器はトラックの音の並びの種類(音高か打楽器か)で決まり、
// トラックの種類は選択肢の並び順だけを決めるため、この欄はその両方を保持する。
export class トラックの楽器選択欄 extends SelectC {
    private _トラック定義: トラック定義

    public constructor(トラック: トラック定義) {
        super({ class: 選択セレクト })
        this._トラック定義 = トラック
        this.トラックを反映する(トラック)
    }

    public トラックを反映する(トラック: トラック定義): this {
        this._トラック定義 = トラック
        this.setOptions(
            音の並びの種類から選べる楽器一覧を取得する(トラック.音の並び.種類, トラック.種類).map((楽器名) => ({
                value: 楽器名,
                text: 楽器名,
                selected: 楽器名 === トラック.楽器,
            })),
        )
        return this
    }

    // 選ばれた綴りはこの欄が出した選択肢のものしか来ないため、音の並びの種類に合わない綴りは配線の誤りとして失敗させる。
    public 選ばれた楽器(): 楽器 {
        const 綴り = this.getValue()
        const 音の並びの種類 = this._トラック定義.音の並び.種類
        for (const 楽器名 of 音の並びの種類から選べる楽器一覧を取得する(音の並びの種類, this._トラック定義.種類)) {
            if (楽器名 === 綴り && トラックの楽器は妥当か(音の並びの種類, 楽器名)) {
                return 楽器名
            }
        }
        throw new Error(`${this._トラック定義.種類}トラックで選べない楽器が選ばれています: ${綴り}`)
    }
}
