import { div, DivC, LV2HtmlComponentBase, 配線ポート } from 'sengen-ui'
import type { I配線可能 } from 'sengen-ui'
import {
    音量と効果の比の下限,
    音量と効果の比の上限,
    遅延のステップ数の下限,
    遅延のステップ数の上限,
    type 楽曲,
    type ミキサー設定,
} from '../../../../../生成/編集資源契約.ts'
import { スライダー項目, 動かしている間は何も伝えない } from '../共通/スライダー項目.ts'
import { ミキサーグリッド } from './スタイル.css.ts'

const 音量と効果の比の刻み幅 = 0.05
const 遅延のステップ数の刻み幅 = 1

// 全体音量・残響・遅延は同じ0から1の比であり、範囲と刻み幅を1箇所に置いて3つの欄で共有する。
function 音量と効果の比のスライダーを作る(ラベル名: string, 初期値: number): スライダー項目 {
    return new スライダー項目(
        ラベル名,
        音量と効果の比の下限,
        音量と効果の比の上限,
        音量と効果の比の刻み幅,
        初期値,
    )
}

export interface Iミキサー設定配線 {
    readonly onミキサー設定変更: (新しいミキサー設定: ミキサー設定) => void
}

// 楽曲全体のミキサー（全体音量・残響・遅延・遅延ステップ数）を調整する部品。
// つまみを動かしている間は数だけが動き、手を離したときに1つだけコマンドを積む(設計正本の判断13)。
export class ミキサー設定部品 extends LV2HtmlComponentBase implements I配線可能<Iミキサー設定配線> {
    protected _componentRoot: DivC
    private readonly _配線: 配線ポート<Iミキサー設定配線> = new 配線ポート<Iミキサー設定配線>('ミキサー設定部品')
    private readonly _全体音量スライダー: スライダー項目
    private readonly _残響スライダー: スライダー項目
    private readonly _遅延量スライダー: スライダー項目
    private readonly _遅延ステップスライダー: スライダー項目
    private _現在の設定: ミキサー設定

    public constructor(初期楽曲: 楽曲) {
        super()
        this._現在の設定 = { ...初期楽曲.ミキサー設定 }
        this._全体音量スライダー = 音量と効果の比のスライダーを作る('全体音量', 初期楽曲.ミキサー設定.全体の音量)
        this._残響スライダー = 音量と効果の比のスライダーを作る('残響の量', 初期楽曲.ミキサー設定.残響の量)
        this._遅延量スライダー = 音量と効果の比のスライダーを作る('遅延の量', 初期楽曲.ミキサー設定.遅延の量)
        this._遅延ステップスライダー = new スライダー項目(
            '遅延ステップ数',
            遅延のステップ数の下限,
            遅延のステップ数の上限,
            遅延のステップ数の刻み幅,
            初期楽曲.ミキサー設定.遅延のステップ数,
            ' ステップ',
        )
        this._componentRoot = div({ class: ミキサーグリッド }).childs([
            this._全体音量スライダー,
            this._残響スライダー,
            this._遅延量スライダー,
            this._遅延ステップスライダー,
        ])
    }

    public 配線する(配線: Iミキサー設定配線): this {
        this._配線.配線する(配線)
        this._全体音量スライダー.配線する({
            on値変更: 動かしている間は何も伝えない,
            on値が決まった: (新音量) => this._ミキサー変更を通知する({ 全体の音量: 新音量 }),
        })
        this._残響スライダー.配線する({
            on値変更: 動かしている間は何も伝えない,
            on値が決まった: (新残響) => this._ミキサー変更を通知する({ 残響の量: 新残響 }),
        })
        this._遅延量スライダー.配線する({
            on値変更: 動かしている間は何も伝えない,
            on値が決まった: (新遅延) => this._ミキサー変更を通知する({ 遅延の量: 新遅延 }),
        })
        this._遅延ステップスライダー.配線する({
            on値変更: 動かしている間は何も伝えない,
            on値が決まった: (新ステップ) => this._ミキサー変更を通知する({ 遅延のステップ数: Math.round(新ステップ) }),
        })
        return this
    }

    public 表示を更新する(楽曲: 楽曲): void {
        this._現在の設定 = { ...楽曲.ミキサー設定 }
        this._全体音量スライダー.値を設定する(楽曲.ミキサー設定.全体の音量)
        this._残響スライダー.値を設定する(楽曲.ミキサー設定.残響の量)
        this._遅延量スライダー.値を設定する(楽曲.ミキサー設定.遅延の量)
        this._遅延ステップスライダー.値を設定する(楽曲.ミキサー設定.遅延のステップ数)
    }

    public override delete(): void {
        this._全体音量スライダー.delete()
        this._残響スライダー.delete()
        this._遅延量スライダー.delete()
        this._遅延ステップスライダー.delete()
        super.delete()
    }

    private _ミキサー変更を通知する(部分更新: Partial<ミキサー設定>): void {
        this._現在の設定 = { ...this._現在の設定, ...部分更新 }
        if (this._配線.配線済みか) {
            this._配線.先.onミキサー設定変更(this._現在の設定)
        }
    }
}
