import { パターンのステップ数, type 曲の節, type パターン } from '../../../../../生成/編集資源契約.ts'
import { 曲全体のステップ数を計算する } from '../../../編集モデル/index.ts'

const 一小節あたりのステップ数 = 16

// 曲構成の再生長やパターンの並びを人が理解しやすい概要文として組み立てる。
export function 曲構成の概要表示文を組み立てる(
    曲構成: readonly 曲の節[],
    パターン一覧: readonly パターン[],
    選択中パターン名乗り: string | null,
): string {
    if (曲構成.length === 0) {
        const 対象パターン = パターン一覧.find((p) => p.名乗り === 選択中パターン名乗り)
        const パターン表示名 = 対象パターン !== undefined ? 対象パターン.表示名 : '未選択'
        const 小節数 = パターンのステップ数 / 一小節あたりのステップ数
        return `全 ${小節数} 小節 (${パターンのステップ数} ステップ) / 現在のパターン「${パターン表示名}」のみループ再生`
    }

    const 全ステップ数 = 曲全体のステップ数を計算する(曲構成)
    const 全小節数 = 全ステップ数 / 一小節あたりのステップ数
    const 節の並び = 曲構成.map((節) => {
        const パターン = パターン一覧.find((p) => p.名乗り === 節.パターンの名乗り)
        const 名前 = パターン !== undefined ? パターン.表示名 : 節.パターンの名乗り
        return `${名前} × ${節.繰り返し回数}`
    }).join(' → ')

    return `全 ${全小節数} 小節 (${全ステップ数} ステップ) / ${節の並び}`
}

// 節を上（手前）へ移動できるかを判定する。
export function 曲の節を上へ移動できるか(位置: number): boolean {
    return 位置 > 0
}

// 節を下（後ろ）へ移動できるかを判定する。
export function 曲の節を下へ移動できるか(位置: number, 全節数: number): boolean {
    return 位置 >= 0 && 位置 < 全節数 - 1
}
