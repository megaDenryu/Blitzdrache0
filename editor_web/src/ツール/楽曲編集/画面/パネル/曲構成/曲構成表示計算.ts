import { type 曲の節, type パターン } from '../../../../../生成/編集資源契約.ts'
import { 小節あたりのステップ数, 曲全体のステップ数を計算する, パターンのステップ数を求める } from '../../../編集モデル/index.ts'

// 曲構成の再生長やパターンの並びを人が理解しやすい概要文として組み立てる。
export function 曲構成の概要表示文を組み立てる(
    曲構成: readonly 曲の節[],
    パターン一覧: readonly パターン[],
    選択中パターン名乗り: string | null,
): string {
    if (曲構成.length === 0) {
        const 対象パターン = パターン一覧.find((p) => p.名乗り === 選択中パターン名乗り)
        const パターン表示名 = 対象パターン !== undefined ? 対象パターン.表示名 : '未選択'
        const ステップ数 = 対象パターン !== undefined ? パターンのステップ数を求める(対象パターン) : 0
        const 小節数 = ステップ数 / 小節あたりのステップ数
        return `全 ${小節数} 小節 (${ステップ数} ステップ) / 現在のパターン「${パターン表示名}」のみループ再生`
    }

    const 全ステップ数 = 曲全体のステップ数を計算する(曲構成, パターン一覧)
    const 全小節数 = 全ステップ数 / 小節あたりのステップ数
    const 節の並び = 曲構成.map((節) => {
        const パターン = パターン一覧.find((p) => p.名乗り === 節.パターンの名乗り)
        const 名前 = パターン !== undefined ? パターン.表示名 : 節.パターンの名乗り
        return `${名前} × ${節.繰り返し回数}`
    }).join(' → ')

    return `全 ${全小節数} 小節 (${全ステップ数} ステップ) / ${節の並び}`
}
