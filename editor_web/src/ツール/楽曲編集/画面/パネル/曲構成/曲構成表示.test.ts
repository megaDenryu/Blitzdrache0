import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import type { パターン, 曲の節 } from '../../../../../生成/編集資源契約.ts'
import {
    曲構成の概要表示文を組み立てる,
    曲の節を上へ移動できるか,
    曲の節を下へ移動できるか,
} from './曲構成表示計算.ts'

describe('曲構成表示計算のテスト', () => {
    const パターン一覧: パターン[] = [
        {
            名乗り: 'pat_1',
            表示名: 'Aメロ',
            進行の参照: { 種類: '既定の進行', 識別子: '戦闘と道' },
            格子: [],
        },
        {
            名乗り: 'pat_2',
            表示名: 'サビ',
            進行の参照: { 種類: '既定の進行', 識別子: '王道進行' },
            格子: [],
        },
    ]

    it('曲構成が空のときに現在のパターンのみループ再生であることが表示されること', () => {
        const 文言 = 曲構成の概要表示文を組み立てる([], パターン一覧, 'pat_1')
        assert.equal(
            文言,
            '全 2 小節 (32 ステップ) / 現在のパターン「Aメロ」のみループ再生',
        )
    })

    it('曲構成が空でないときに全体の小節数・ステップ数・節の連なりが表示されること', () => {
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'pat_1', 繰り返し回数: 2 },
            { パターンの名乗り: 'pat_2', 繰り返し回数: 1 },
        ]
        const 文言 = 曲構成の概要表示文を組み立てる(曲構成, パターン一覧, 'pat_1')
        // pat_1 (32ステップ) × 2 + pat_2 (32ステップ) × 1 = 96ステップ = 6小節
        assert.equal(
            文言,
            '全 6 小節 (96 ステップ) / Aメロ × 2 → サビ × 1',
        )
    })

    it('節の上下移動の可否判定が正しいこと', () => {
        assert.equal(曲の節を上へ移動できるか(0), false)
        assert.equal(曲の節を上へ移動できるか(1), true)

        assert.equal(曲の節を下へ移動できるか(0, 3), true)
        assert.equal(曲の節を下へ移動できるか(1, 3), true)
        assert.equal(曲の節を下へ移動できるか(2, 3), false)
    })
})
