import {
    曲の節の繰り返し回数の下限,
    曲の節の繰り返し回数の上限,
    type 曲の節,
    type パターン,
} from '../../../../../生成/編集資源契約.ts'
import type { セレクトの選択肢 } from '../共通/セレクトの選択肢.ts'

// 曲構成の1つの節が持つ2つの欄(どのパターンを・何回繰り返すか)の選択肢と、
// 選ばれた綴りを型契約の値へ戻す変換を持つ。

export function 節のパターン選択肢一覧を組み立てる(
    節: 曲の節,
    パターン一覧: readonly パターン[],
): セレクトの選択肢[] {
    return パターン一覧.map((パターン) => ({
        value: パターン.名乗り,
        text: `${パターン.表示名} (${パターン.名乗り})`,
        selected: パターン.名乗り === 節.パターンの名乗り,
    }))
}

export function 節の繰り返し回数の選択肢一覧を組み立てる(節: 曲の節): セレクトの選択肢[] {
    const 選択肢一覧: セレクトの選択肢[] = []
    for (let 回数 = 曲の節の繰り返し回数の下限; 回数 <= 曲の節の繰り返し回数の上限; 回数++) {
        選択肢一覧.push({ value: 回数.toString(), text: `${回数} 回`, selected: 回数 === 節.繰り返し回数 })
    }
    return 選択肢一覧
}

// 選ばれた綴りは上の組み立てが出したものしか来ないため、範囲の外は既定値で埋めずに失敗させる。
export function 綴りから繰り返し回数を復元する(綴り: string): number {
    const 回数 = Number.parseInt(綴り, 10)
    if (!Number.isInteger(回数) || 回数 < 曲の節の繰り返し回数の下限 || 回数 > 曲の節の繰り返し回数の上限) {
        throw new Error(`曲の節の繰り返し回数として読めない綴りです: ${綴り}`)
    }
    return 回数
}
