import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import type { パターン } from '../../../../../生成/編集資源契約.ts'
import {
    パターンを削除できるか,
    新規パターンの名乗りを発番する,
    新規パターンの表示名を生成する,
} from './パターン操作判定.ts'

describe('パターン操作判定のテスト', () => {
    it('パターンが1つのときに削除できないこと', () => {
        assert.equal(パターンを削除できるか(1), false)
        assert.equal(パターンを削除できるか(0), false)
        assert.equal(パターンを削除できるか(2), true)
        assert.equal(パターンを削除できるか(5), true)
    })

    it('既存の名乗りと重複しない名乗りが発番されること', () => {
        const パターン一覧: パターン[] = [
            {
                名乗り: 'pat_1',
                表示名: 'パターン 1',
                小節数: 2,
                進行の参照: { 種類: '既定の進行', 識別子: '戦闘と道' },
                格子: [],
            },
            {
                名乗り: 'pat_2',
                表示名: 'パターン 2',
                小節数: 2,
                進行の参照: { 種類: '既定の進行', 識別子: '戦闘と道' },
                格子: [],
            },
        ]
        const 新規名乗り = 新規パターンの名乗りを発番する(パターン一覧)
        assert.equal(新規名乗り, 'pat_3')

        const 新規表示名 = 新規パターンの表示名を生成する(パターン一覧)
        assert.equal(新規表示名, 'パターン 3')
    })

    it('中抜けがある場合でも重複しない名乗りが発番されること', () => {
        const パターン一覧: パターン[] = [
            {
                名乗り: 'pat_1',
                表示名: 'パターン 1',
                小節数: 2,
                進行の参照: { 種類: '既定の進行', 識別子: '戦闘と道' },
                格子: [],
            },
            {
                名乗り: 'pat_3',
                表示名: 'パターン 3',
                小節数: 2,
                進行の参照: { 種類: '既定の進行', 識別子: '戦闘と道' },
                格子: [],
            },
        ]
        const 新規名乗り = 新規パターンの名乗りを発番する(パターン一覧)
        assert.notEqual(新規名乗り, 'pat_1')
        assert.notEqual(新規名乗り, 'pat_3')
    })
})
