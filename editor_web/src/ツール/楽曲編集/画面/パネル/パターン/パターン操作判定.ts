import {
    既定のコード進行一覧,
    type コード進行参照,
    type パターン,
} from '../../../../../生成/編集資源契約.ts'

// パターンが1つしか無いときは削除できない（最低1つのパターンが必要）。
export function パターンを削除できるか(パターン数: number): boolean {
    return パターン数 > 1
}

// 既存パターン一覧と重複しない一意なパターンの名乗りを発番する。
export function 新規パターンの名乗りを発番する(既存パターン一覧: readonly パターン[]): string {
    const 既存名乗り集合 = new Set(既存パターン一覧.map((p) => p.名乗り))
    let 番号 = 既存パターン一覧.length + 1
    while (既存名乗り集合.has(`pat_${番号}`)) {
        番号++
    }
    return `pat_${番号}`
}

// 新規パターンの分かりやすい初期表示名を生成する。
export function 新規パターンの表示名を生成する(既存パターン一覧: readonly パターン[]): string {
    const 既存表示名集合 = new Set(既存パターン一覧.map((p) => p.表示名))
    let 番号 = 既存パターン一覧.length + 1
    while (既存表示名集合.has(`パターン ${番号}`)) {
        番号++
    }
    return `パターン ${番号}`
}

// 選択中の名乗りから編集対象のパターンを決める。名乗りが無いときは先頭のパターンを対象にする。
export function 選択中のパターンを探す(
    パターン一覧: readonly パターン[],
    選択中名乗り: string | null,
): パターン | null {
    const 対象 = 選択中名乗り === null
        ? パターン一覧[0]
        : パターン一覧.find((パターン) => パターン.名乗り === 選択中名乗り)
    return 対象 === undefined ? null : 対象
}

// 新規パターンへ最初に与えるコード進行の参照。既定の進行は型契約が持つ定数であり、
// 空であることは型契約の生成が壊れていることを意味するため、綴りを書き足さずに失敗させる。
export function 新規パターンの初期の進行の参照を決める(): コード進行参照 {
    const 先頭の既定進行 = 既定のコード進行一覧[0]
    if (先頭の既定進行 === undefined) {
        throw new Error('既定のコード進行一覧が空です')
    }
    return { 種類: '既定の進行', 識別子: 先頭の既定進行.識別子 }
}
