import type { パターン, トラック定義 } from '../../../../../生成/編集資源契約.ts'

export interface 進行利用状況 {
    readonly 利用パターン名一覧: readonly string[]
    readonly 利用トラック名一覧: readonly string[]
}

// 指定した独自進行の名前を参照しているパターンおよびトラックを調べる。
export function 独自進行の利用状況を調べる(
    進行名: string,
    パターン一覧: readonly パターン[],
    トラック構成: readonly トラック定義[],
): 進行利用状況 {
    const 利用パターン名一覧: string[] = []
    for (const パターン of パターン一覧) {
        if (パターン.進行の参照.種類 === '独自の進行' && パターン.進行の参照.名前 === 進行名) {
            利用パターン名一覧.push(パターン.表示名)
        }
    }

    const 利用トラック名一覧: string[] = []
    for (const トラック of トラック構成) {
        if (トラック.進行の割り当て?.種類 === '独自の進行' && トラック.進行の割り当て.名前 === 進行名) {
            利用トラック名一覧.push(トラック.表示名)
        }
    }

    return { 利用パターン名一覧, 利用トラック名一覧 }
}

// いまこの進行がどこで使われているかを1行で答える。保存した進行が一覧に出たあと、
// どれが実際に鳴っているのかを人が見分けられるようにするために要る。
export function 独自進行の利用中の要約を組み立てる(利用状況: 進行利用状況): string {
    const 使い先: string[] = []
    if (利用状況.利用パターン名一覧.length > 0) {
        使い先.push(`パターン ${利用状況.利用パターン名一覧.join(', ')}`)
    }
    if (利用状況.利用トラック名一覧.length > 0) {
        使い先.push(`トラック ${利用状況.利用トラック名一覧.join(', ')}`)
    }
    return 使い先.length === 0 ? '未使用' : `使用中: ${使い先.join(' / ')}`
}

// 独自進行の削除に伴う影響（どこで使われているか）の警告文を組み立てる。
export function 独自進行の削除影響文を組み立てる(利用状況: 進行利用状況): string | null {
    const 件数 = 利用状況.利用パターン名一覧.length + 利用状況.利用トラック名一覧.length
    if (件数 === 0) {
        return null
    }

    const 影響箇所: string[] = []
    if (利用状況.利用パターン名一覧.length > 0) {
        影響箇所.push(`パターン「${利用状況.利用パターン名一覧.join(', ')}」`)
    }
    if (利用状況.利用トラック名一覧.length > 0) {
        影響箇所.push(`トラック「${利用状況.利用トラック名一覧.join(', ')}」`)
    }

    return `注意: ${影響箇所.join('および')}が、この進行を指しています。削除すると指し先が失われ、その和音を解決できなくなります。`
}
