import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import type { パターン, トラック定義 } from '../../../../../生成/編集資源契約.ts'
import {
    独自進行の利用状況を調べる,
    独自進行の削除影響文を組み立てる,
    独自進行の利用中の要約を組み立てる,
} from './進行利用状況計算.ts'

describe('進行利用状況計算のテスト', () => {
    const パターン一覧: パターン[] = [
        {
            名乗り: 'pat_1',
            表示名: 'イントロ',
            小節数: 2,
            進行の参照: { 種類: '独自の進行', 名前: 'マイ進行A' },
            格子: [],
        },
        {
            名乗り: 'pat_2',
            表示名: 'サビ',
            小節数: 2,
            進行の参照: { 種類: '既定の進行', 識別子: '王道進行' },
            格子: [],
        },
    ]

    const トラック構成: トラック定義[] = [
        {
            表示名: 'Melody',
            種類: '旋律',
            音の並び: { 種類: '音高の行一覧', 値: [72] },
            楽器: 'グランドピアノ',
            音量: 1.0,
            進行の割り当て: null,
        },
        {
            表示名: 'Backing',
            種類: '伴奏',
            音の並び: { 種類: '音高の行一覧', 値: [60] },
            楽器: 'アコースティックギター',
            音量: 0.8,
            進行の割り当て: { 種類: '独自の進行', 名前: 'マイ進行A' },
        },
    ]

    it('使用中の独自進行の利用パターンと利用トラックが特定できること', () => {
        const 利用状況 = 独自進行の利用状況を調べる('マイ進行A', パターン一覧, トラック構成)
        assert.deepEqual(利用状況.利用パターン名一覧, ['イントロ'])
        assert.deepEqual(利用状況.利用トラック名一覧, ['Backing'])

        const 警告文 = 独自進行の削除影響文を組み立てる(利用状況)
        assert.notEqual(警告文, null)
        assert.match(警告文 ?? '', /イントロ/)
        assert.match(警告文 ?? '', /Backing/)
    })

    it('使用中かどうかが1行の要約に出ること', () => {
        const 使われている = 独自進行の利用状況を調べる('マイ進行A', パターン一覧, トラック構成)
        const 要約 = 独自進行の利用中の要約を組み立てる(使われている)
        assert.match(要約, /^使用中: /)
        assert.match(要約, /イントロ/)
        assert.match(要約, /Backing/)

        const 使われていない = 独自進行の利用状況を調べる('未使用進行', パターン一覧, トラック構成)
        assert.strictEqual(独自進行の利用中の要約を組み立てる(使われていない), '未使用')
    })

    it('使用されていない独自進行のときは利用状況が空になり警告文がnullになること', () => {
        const 利用状況 = 独自進行の利用状況を調べる('未使用進行', パターン一覧, トラック構成)
        assert.deepEqual(利用状況.利用パターン名一覧, [])
        assert.deepEqual(利用状況.利用トラック名一覧, [])

        const 警告文 = 独自進行の削除影響文を組み立てる(利用状況)
        assert.equal(警告文, null)
    })
})
