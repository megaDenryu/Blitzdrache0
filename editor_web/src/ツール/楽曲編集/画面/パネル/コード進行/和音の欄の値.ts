import {
    和音の根音の下限,
    和音の根音の上限,
    和音の続くステップ数の下限,
    和音の続くステップ数の上限,
    type 和音の種類,
} from '../../../../../生成/編集資源契約.ts'
import { ピッチクラスの音名表記 } from '../../音名表示.ts'
import type { セレクトの選択肢 } from '../共通/セレクトの選択肢.ts'

// 独自進行の和音1件が持つ3つの欄(根音・種類・続くステップ数)の選択肢と、
// 選ばれた綴りを型契約の値へ戻す変換を持つ。

const 和音の種類一覧: readonly 和音の種類[] = [
    '長三和音',
    '短三和音',
    '長七の和音',
    '短七の和音',
    '属七の和音',
    '四度掛留の和音',
    '減三和音',
    '増三和音',
]

// 拍の割り切れる長さだけを出す。1ステップは16分音符1つ分であり、4で1拍、16で1小節になる。
const 続くステップ数の候補一覧: readonly number[] = [1, 2, 4, 8, 16, 32]

export const 和音の既定の続くステップ数 = 4

export function 根音の選択肢一覧を組み立てる(選ばれている根音: number): セレクトの選択肢[] {
    const 選択肢一覧: セレクトの選択肢[] = []
    for (let 根音 = 和音の根音の下限; 根音 <= 和音の根音の上限; 根音++) {
        選択肢一覧.push({
            value: 根音.toString(),
            text: ピッチクラスの音名表記(根音),
            selected: 根音 === 選ばれている根音,
        })
    }
    return 選択肢一覧
}

export function 和音の種類の選択肢一覧を組み立てる(選ばれている種類: 和音の種類): セレクトの選択肢[] {
    return 和音の種類一覧.map((種類) => ({ value: 種類, text: 種類, selected: 種類 === 選ばれている種類 }))
}

export function 続くステップ数の選択肢一覧を組み立てる(選ばれているステップ数: number): セレクトの選択肢[] {
    return 続くステップ数の候補一覧
        .filter((ステップ数) => ステップ数 >= 和音の続くステップ数の下限 && ステップ数 <= 和音の続くステップ数の上限)
        .map((ステップ数) => ({
            value: ステップ数.toString(),
            text: `${ステップ数} ステップ`,
            selected: ステップ数 === 選ばれているステップ数,
        }))
}

// 以下の復元は、上の組み立てが出した綴りしか受け取らない。読めない綴りは画面の配線の誤りであり、
// 既定値で埋めると誤った和音が黙って保存されるため失敗させる。

export function 綴りから根音を復元する(綴り: string): number {
    const 根音 = Number.parseInt(綴り, 10)
    if (!Number.isInteger(根音) || 根音 < 和音の根音の下限 || 根音 > 和音の根音の上限) {
        throw new Error(`和音の根音として読めない綴りです: ${綴り}`)
    }
    return 根音
}

export function 綴りから和音の種類を復元する(綴り: string): 和音の種類 {
    for (const 種類 of 和音の種類一覧) {
        if (種類 === 綴り) return 種類
    }
    throw new Error(`和音の種類として読めない綴りです: ${綴り}`)
}

export function 綴りから続くステップ数を復元する(綴り: string): number {
    const ステップ数 = Number.parseInt(綴り, 10)
    if (!Number.isInteger(ステップ数) || ステップ数 < 和音の続くステップ数の下限 || ステップ数 > 和音の続くステップ数の上限) {
        throw new Error(`和音の続くステップ数として読めない綴りです: ${綴り}`)
    }
    return ステップ数
}
