import {
    既定のコード進行一覧,
    type コード進行,
    type コード進行参照,
} from '../../../../../生成/編集資源契約.ts'
import type { セレクトの選択肢 } from './セレクトの選択肢.ts'

// セレクトが扱えるのは文字列だけであるため、判別共用体であるコード進行参照を文字列へ写して運ぶ。
// 文字列と復元をこの1箇所へ閉じ、パネルの側では判別共用体のまま扱う。
const 楽曲全体に従う文字列 = '全体に従う'
const 既定の進行の接頭辞 = '既定:'
const 独自の進行の接頭辞 = '独自:'

export type 進行の選び =
    | { readonly 種類: '楽曲全体の進行に従う' }
    | { readonly 種類: 'この進行を使う', readonly 参照: コード進行参照 }

function コード進行参照を文字列へ写す(参照: コード進行参照): string {
    switch (参照.種類) {
        case '既定の進行':
            return `${既定の進行の接頭辞}${参照.識別子}`
        case '独自の進行':
            return `${独自の進行の接頭辞}${参照.名前}`
    }
}

function 参照が一致するか(選ばれている: コード進行参照 | null, 候補: コード進行参照): boolean {
    return 選ばれている !== null && コード進行参照を文字列へ写す(選ばれている) === コード進行参照を文字列へ写す(候補)
}

function 進行ごとの選択肢一覧を並べる(
    選ばれている: コード進行参照 | null,
    独自進行一覧: readonly コード進行[],
): セレクトの選択肢[] {
    const 選択肢一覧: セレクトの選択肢[] = []
    for (const 進行 of 既定のコード進行一覧) {
        const 候補: コード進行参照 = { 種類: '既定の進行', 識別子: 進行.識別子 }
        選択肢一覧.push({
            value: コード進行参照を文字列へ写す(候補),
            text: `既定: ${進行.表示名}`,
            selected: 参照が一致するか(選ばれている, 候補),
        })
    }
    for (const 進行 of 独自進行一覧) {
        const 候補: コード進行参照 = { 種類: '独自の進行', 名前: 進行.名前 }
        選択肢一覧.push({
            value: コード進行参照を文字列へ写す(候補),
            text: `独自: ${進行.名前}`,
            selected: 参照が一致するか(選ばれている, 候補),
        })
    }
    return 選択肢一覧
}

// トラックの進行の割り当ての選択肢一覧。割り当てが無い状態を先頭の選択肢として明示する。
export function トラックの進行の選択肢一覧を組み立てる(
    進行の割り当て: コード進行参照 | null,
    独自進行一覧: readonly コード進行[],
): セレクトの選択肢[] {
    return [
        {
            value: 楽曲全体に従う文字列,
            text: '楽曲全体の進行に従う',
            selected: 進行の割り当て === null,
        },
        ...進行ごとの選択肢一覧を並べる(進行の割り当て, 独自進行一覧),
    ]
}

// パターンの進行の選択肢一覧。パターンは必ず進行を1つ持つため、楽曲全体に従う選択肢は出さない。
export function パターンの進行の選択肢一覧を組み立てる(
    進行の参照: コード進行参照,
    独自進行一覧: readonly コード進行[],
): セレクトの選択肢[] {
    return 進行ごとの選択肢一覧を並べる(進行の参照, 独自進行一覧)
}

// 選ばれた文字列を進行の選びへ戻す。この文字列は上の組み立てが出したものしか来ないため、
// 読めない文字列は画面の配線の誤りであり、既定値で埋めずに失敗させる。
export function 文字列から進行の選びを復元する(文字列: string): 進行の選び {
    if (文字列 === 楽曲全体に従う文字列) {
        return { 種類: '楽曲全体の進行に従う' }
    }
    if (文字列.startsWith(既定の進行の接頭辞)) {
        return { 種類: 'この進行を使う', 参照: { 種類: '既定の進行', 識別子: 文字列.slice(既定の進行の接頭辞.length) } }
    }
    if (文字列.startsWith(独自の進行の接頭辞)) {
        return { 種類: 'この進行を使う', 参照: { 種類: '独自の進行', 名前: 文字列.slice(独自の進行の接頭辞.length) } }
    }
    throw new Error(`コード進行の選択肢として読めない文字列です: ${文字列}`)
}
