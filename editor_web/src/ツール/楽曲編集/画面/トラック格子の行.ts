import { div, DivC } from 'sengen-ui'
import type { トラック定義, 和音 } from '../../../生成/編集資源契約.ts'
import { 数値からセルへ変換する, トラックの行の音はステップで許されるか } from '../編集モデル/index.ts'
import { 見込みを反映したセルを計算する } from './見込みセル計算.ts'
import type { 打ち込みドラッグ見込み, 升目の当たりの記録 } from './打ち込み見込み.ts'
import { 行枠, 行見出し, 升目列 } from './スタイル.css.ts'
import { 打ち込み升目部品 } from './打ち込み升目部品.ts'
import { トラック行の表示名 } from './音名表示.ts'

// パターンの名乗り取得・押下・進入の3つは、升目1つ1つの当たりの記録を組み立てるために
// 常に組で使われるため1つの配線としてまとめる(トラック格子部品からの引数束ね)。
export type 升目当たり配線 = {
    readonly パターンの名乗り取得: () => string
    readonly on升目押下: (当たり: 升目の当たりの記録, ボタン: number) => void
    readonly on升目進入: (当たり: 升目の当たりの記録) => void
}

export type 格子の行構築結果 = {
    readonly 升目一覧: readonly 打ち込み升目部品[]
    readonly 行要素: DivC
}

// トラックの1行ぶんの見出しと升目列を組み立てる(トラック格子部品からの工程分離)。
// 呼び出し元は組み立てた升目一覧とDOM要素だけを受け取り、押下・進入の配線の中身を知らずに使える。
export function 格子の1行を構築する(
    トラック: トラック定義,
    トラックの位置: number,
    行位置: number,
    ステップ数: number,
    配線: 升目当たり配線,
): 格子の行構築結果 {
    const 表示名 = トラック行の表示名(トラック.音の並び, 行位置)
    const 行見出し要素 = div({ class: 行見出し, text: 表示名 }).setTooltip(表示名)
    const 升目一覧: 打ち込み升目部品[] = []

    for (let ステップ = 0; ステップ < ステップ数; ステップ++) {
        const 升目 = new 打ち込み升目部品(ステップ)
        const 当たりを作る = (): 升目の当たりの記録 => ({
            パターンの名乗り: 配線.パターンの名乗り取得(),
            トラックの位置,
            行の位置: 行位置,
            ステップ,
        })
        升目.onポインタ押下((ボタン) => 配線.on升目押下(当たりを作る(), ボタン))
        升目.onポインタ進入(() => 配線.on升目進入(当たりを作る()))
        升目一覧.push(升目)
    }

    const 升目列要素 = div({ class: 升目列 }).childs(升目一覧)
    const 行要素 = div({ class: 行枠 }).childs([行見出し要素, 升目列要素])
    return { 升目一覧, 行要素 }
}

// 打点の表示更新が触れるトラック・和音・ドラッグ見込み・ステップ数は行ごとに変わらないため1つにまとめる
// (常に組で渡される引数の束ね)。
export type 打点表示の当てどころ = {
    readonly トラック: トラック定義
    readonly パターンの名乗り: string
    readonly トラックの位置: number
    readonly 和音一覧: readonly 和音[] | null
    readonly ドラッグ見込み: 打ち込みドラッグ見込み | null
    readonly ステップ数: number
}

// 1行ぶんの打点の表示を、対象セルと許されるかの判定を通して升目一覧へ反映する(トラック格子部品からの工程分離)。
export function 格子の1行の打点を反映する(
    行データ: readonly number[],
    行位置: number,
    升目一覧: readonly 打ち込み升目部品[],
    当てどころ: 打点表示の当てどころ,
): void {
    for (let ステップ = 0; ステップ < 当てどころ.ステップ数; ステップ++) {
        const 生値 = 行データ[ステップ]
        const 升目部品 = 升目一覧[ステップ]
        if (生値 === undefined || 升目部品 === undefined) continue

        const 対象セル = 見込みを反映したセルを計算する(
            数値からセルへ変換する(生値),
            当てどころ.パターンの名乗り,
            当てどころ.トラックの位置,
            行位置,
            ステップ,
            当てどころ.ドラッグ見込み,
        )
        const 許されるか = トラックの行の音はステップで許されるか(当てどころ.トラック, 行位置, ステップ, 当てどころ.和音一覧)
        升目部品.表示を更新する(対象セル, 許されるか)
    }
}
