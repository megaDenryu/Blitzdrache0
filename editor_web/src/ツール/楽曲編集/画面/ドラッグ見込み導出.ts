import type { 打ち込みドラッグ見込み, 升目の当たりの記録 } from './打ち込み見込み.ts'

// 起点と現在の当たり位置から、表示用のドラッグ見込みを導出する。
export function ドラッグ見込みを導出する(
    起点: 升目の当たりの記録,
    現在: 升目の当たりの記録,
    ボタン: number,
    進行に従うか: boolean,
): 打ち込みドラッグ見込み {
    const 同じ行か = 起点.パターンの名乗り === 現在.パターンの名乗り
        && 起点.トラックの位置 === 現在.トラックの位置
        && 起点.行の位置 === 現在.行の位置

    if (ボタン === 0) {
        if (同じ行か && 起点.ステップ !== 現在.ステップ) {
            return {
                種類: '音を伸ばす',
                対象: { パターンの名乗り: 起点.パターンの名乗り, トラックの位置: 起点.トラックの位置, 行の位置: 起点.行の位置 },
                始まりのステップ: 起点.ステップ,
                終わりのステップ: 現在.ステップ,
                進行に従うか,
            }
        }
        const 確定 = 同じ行か ? 起点 : 現在
        return {
            種類: '打点を置く',
            対象: { パターンの名乗り: 確定.パターンの名乗り, トラックの位置: 確定.トラックの位置, 行の位置: 確定.行の位置 },
            ステップ: 確定.ステップ,
            進行に従うか,
        }
    }

    if (同じ行か && 起点.ステップ !== 現在.ステップ) {
        return {
            種類: '範囲の打点を消す',
            対象: { パターンの名乗り: 起点.パターンの名乗り, トラックの位置: 起点.トラックの位置, 行の位置: 起点.行の位置 },
            始まりのステップ: 起点.ステップ,
            終わりのステップ: 現在.ステップ,
        }
    }
    const 確定 = 同じ行か ? 起点 : 現在
    return {
        種類: '打点を消す',
        対象: { パターンの名乗り: 確定.パターンの名乗り, トラックの位置: 確定.トラックの位置, 行の位置: 確定.行の位置 },
        ステップ: 確定.ステップ,
    }
}
