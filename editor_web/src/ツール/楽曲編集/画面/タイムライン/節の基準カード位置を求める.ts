import type { カード位置 } from '../../編集モデル/index.ts'

// 節の枠が持つ操作は枠の先頭のカードの位置を基準にするが、選択中のカードが同じ節にあるなら
// その繰り返し・小節を保つため選択中のカードの位置を基準にする
// (前へ移動・後へ移動が守ってきた規律を、削除・複製・挿入を含む全操作へ広げる。issue #87)。
export function 節の基準カード位置を求める(
    先頭カードの位置: カード位置,
    選択中のカード: カード位置 | null,
): カード位置 {
    if (選択中のカード !== null && 選択中のカード.節の位置 === 先頭カードの位置.節の位置) {
        return 選択中のカード
    }
    return 先頭カードの位置
}
