import type { カード位置, 曲構成のカード } from '../../編集モデル/index.ts'

// 同じ節に属するカードの列1つを表す。先頭カードの位置は節の枠の移動操作がそのまま使う
// (枠の先頭のカードの位置を渡せば移動先が節ごとに解決される、issue #88)。
export type 節ごとのカード列 = {
    readonly 節の位置: number
    readonly 先頭カードの位置: カード位置
    readonly パターンの名乗り: string
    readonly カード列: readonly 曲構成のカード[]
}

// タイムラインのカードの列を、同じ節に属するカードごとに切り分ける(節の枠へ渡す単位)。
// カードの列は節の位置の昇順に並んでいる前提であり、隣り合うカードの節の位置を比べるだけで切れる。
export function カード列を節ごとに切る(カード列: readonly 曲構成のカード[]): readonly 節ごとのカード列[] {
    const 結果: 節ごとのカード列[] = []
    for (const カード of カード列) {
        const 末尾 = 結果[結果.length - 1]
        if (末尾 !== undefined && 末尾.節の位置 === カード.位置.節の位置) {
            結果[結果.length - 1] = { ...末尾, カード列: [...末尾.カード列, カード] }
        } else {
            結果.push({
                節の位置: カード.位置.節の位置,
                先頭カードの位置: カード.位置,
                パターンの名乗り: カード.パターンの名乗り,
                カード列: [カード],
            })
        }
    }
    return 結果
}
