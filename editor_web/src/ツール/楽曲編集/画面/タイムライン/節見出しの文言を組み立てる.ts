import type { パターン } from '../../../../生成/編集資源契約.ts'
import { パターンの表示名を探す } from './パターンの表示名を探す.ts'

// 節の枠の見出しの文言を組み立てる。パターンの表示名と繰り返し回数を「A × 2」の形で示し、
// 回数が1のときは回数を出さず表示名だけにする(設計正本`_doc/設計/楽曲エディター.md`判断15の是正、issue #88)。
export function 節見出しの文言を組み立てる(
    パターンの名乗り: string,
    繰り返し回数: number,
    パターン一覧: readonly パターン[],
): string {
    const 表示名 = パターンの表示名を探す(パターンの名乗り, パターン一覧)
    return 繰り返し回数 <= 1 ? 表示名 : `${表示名} × ${繰り返し回数}`
}
