import type { パターン } from '../../../../生成/編集資源契約.ts'

// パターンの名乗りから表示名を探す。見つからなければ名乗りをそのまま返す(カード部品と節の枠部品が共有する)。
export function パターンの表示名を探す(パターンの名乗り: string, パターン一覧: readonly パターン[]): string {
    const パターン = パターン一覧.find((p) => p.名乗り === パターンの名乗り)
    return パターン !== undefined ? パターン.表示名 : パターンの名乗り
}
