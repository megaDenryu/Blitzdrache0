import type { 曲の節 } from '../../../../生成/編集資源契約.ts'
import { カードの操作をコマンドへ写す } from '../../操作コマンド/index.ts'
import type { カード位置 } from '../../編集モデル/index.ts'
import type { 節の操作の種類 } from './節の操作の種類.ts'

// 押せるかどうかを操作の種類ごとに問える形。呼び出し側(節の枠一覧を組み立てる)が
// `カードの操作をコマンドへ写す`の結果から組み立てる。
export type 節の操作の押せるか = { readonly [K in 節の操作の種類]: boolean }

// 節の枠が持つ6つの操作を、基準にするカード位置で実際にコマンドへ写して試し、押せるかどうかへ変換する。
// 押せない操作を押せる状態で出さないため、判定は実際の写しの結果に委ねる(自前で条件を再現しない)。
export function 節の操作の押せるかを計算する(曲構成: readonly 曲の節[], 基準位置: カード位置): 節の操作の押せるか {
    const 押せるか = (種類: 節の操作の種類): boolean =>
        カードの操作をコマンドへ写す(曲構成, { 種類, 位置: 基準位置 }).種類 !== 'できない'

    return {
        前へ挿入: 押せるか('前へ挿入'),
        複製: 押せるか('複製'),
        削除: 押せるか('削除'),
        後へ挿入: 押せるか('後へ挿入'),
        前へ移動: 押せるか('前へ移動'),
        後へ移動: 押せるか('後へ移動'),
    }
}
