import type { 曲の節 } from '../../../../生成/編集資源契約.ts'
import { カードの操作をコマンドへ写す } from '../../操作コマンド/index.ts'
import type { カード位置 } from '../../編集モデル/index.ts'
import type { 節移動の種類 } from './節移動の種類.ts'

// 押せるかどうかを移動の種類ごとに問える形(カード操作の押せるかの節の枠版)。
export type 節移動の押せるか = { readonly [K in 節移動の種類]: boolean }

// 節の枠が持つ2つの移動操作を、先頭カードの位置で実際にコマンドへ写して試し、押せるかどうかへ変換する。
// 先頭は先頭の節へ、末尾は末尾の節へ移動できないため、その両端で押せない状態になる。
export function 節移動の押せるかを計算する(曲構成: readonly 曲の節[], 先頭カードの位置: カード位置): 節移動の押せるか {
    const 押せるか = (種類: 節移動の種類): boolean =>
        カードの操作をコマンドへ写す(曲構成, { 種類, 位置: 先頭カードの位置 }).種類 !== 'できない'

    return {
        前へ移動: 押せるか('前へ移動'),
        後へ移動: 押せるか('後へ移動'),
    }
}
