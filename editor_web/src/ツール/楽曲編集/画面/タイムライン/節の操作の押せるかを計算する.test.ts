import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { 曲の節 } from '../../../../生成/編集資源契約.ts'
import { 節の操作の押せるかを計算する } from './節の操作の押せるかを計算する.ts'

describe('節の操作の押せるかを計算するテスト', () => {
    it('先頭の節は前へ移動できず、後へ移動できること', () => {
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'A', 繰り返し回数: 1 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
        ]
        const 押せるか = 節の操作の押せるかを計算する(曲構成, { 節の位置: 0, 繰り返しの何回目: 0, 小節の番号: 0 })
        assert.equal(押せるか.前へ移動, false)
        assert.equal(押せるか.後へ移動, true)
    })

    it('末尾の節は後へ移動できず、前へ移動できること', () => {
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'A', 繰り返し回数: 1 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
        ]
        const 押せるか = 節の操作の押せるかを計算する(曲構成, { 節の位置: 1, 繰り返しの何回目: 0, 小節の番号: 0 })
        assert.equal(押せるか.前へ移動, true)
        assert.equal(押せるか.後へ移動, false)
    })

    it('中間の節はどちらへも移動できること', () => {
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'A', 繰り返し回数: 1 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
            { パターンの名乗り: 'C', 繰り返し回数: 1 },
        ]
        const 押せるか = 節の操作の押せるかを計算する(曲構成, { 節の位置: 1, 繰り返しの何回目: 0, 小節の番号: 0 })
        assert.equal(押せるか.前へ移動, true)
        assert.equal(押せるか.後へ移動, true)
    })

    it('節が1つしか無いとき、削除はできないが複製はできること', () => {
        const 曲構成: 曲の節[] = [{ パターンの名乗り: 'A', 繰り返し回数: 1 }]
        const 押せるか = 節の操作の押せるかを計算する(曲構成, { 節の位置: 0, 繰り返しの何回目: 0, 小節の番号: 0 })
        assert.equal(押せるか.削除, true)
        assert.equal(押せるか.複製, true)
        assert.equal(押せるか.前へ挿入, true)
        assert.equal(押せるか.後へ挿入, true)
    })
})
