import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { パターン, 曲の節 } from '../../../../生成/編集資源契約.ts'
import { 曲構成をカードの列へ展開する } from '../../編集モデル/index.ts'
import { カード列を節ごとに切る } from './カード列を節ごとに切る.ts'

function パターンを組み立てる(名乗り: string, 小節数: number): パターン {
    return {
        名乗り,
        表示名: 名乗り,
        小節数,
        進行の参照: { 種類: '既定の進行', 識別子: 'C' },
        格子: [],
    }
}

describe('カード列を節ごとに切るテスト', () => {
    const パターン一覧: パターン[] = [パターンを組み立てる('A', 1), パターンを組み立てる('B', 1)]

    it('空のカード列なら空の列を返すこと', () => {
        assert.deepEqual(カード列を節ごとに切る([]), [])
    })

    it('A×2, B×1の曲構成を、節ごとの2つのグループへ切ること', () => {
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'A', 繰り返し回数: 2 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
        ]
        const グループ列 = カード列を節ごとに切る(曲構成をカードの列へ展開する(曲構成, パターン一覧))

        assert.equal(グループ列.length, 2)

        assert.equal(グループ列[0].節の位置, 0)
        assert.equal(グループ列[0].パターンの名乗り, 'A')
        assert.equal(グループ列[0].カード列.length, 2)
        assert.deepEqual(グループ列[0].先頭カードの位置, { 節の位置: 0, 繰り返しの何回目: 0, 小節の番号: 0 })

        assert.equal(グループ列[1].節の位置, 1)
        assert.equal(グループ列[1].パターンの名乗り, 'B')
        assert.equal(グループ列[1].カード列.length, 1)
        assert.deepEqual(グループ列[1].先頭カードの位置, { 節の位置: 1, 繰り返しの何回目: 0, 小節の番号: 0 })
    })

    it('A×1, B×1, A×1のように同じパターンが離れて並んでも、節の位置ごとに別グループへ切ること', () => {
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'A', 繰り返し回数: 1 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
            { パターンの名乗り: 'A', 繰り返し回数: 1 },
        ]
        const グループ列 = カード列を節ごとに切る(曲構成をカードの列へ展開する(曲構成, パターン一覧))

        assert.equal(グループ列.length, 3)
        assert.deepEqual(グループ列.map((グループ) => グループ.節の位置), [0, 1, 2])
    })

    it('小節数が2のパターンを含む節では、1つの節から2枚のカードへ切り分けること', () => {
        const パターン一覧2: パターン[] = [パターンを組み立てる('A', 2), パターンを組み立てる('B', 1)]
        const 曲構成: 曲の節[] = [
            { パターンの名乗り: 'A', 繰り返し回数: 1 },
            { パターンの名乗り: 'B', 繰り返し回数: 1 },
        ]
        const グループ列 = カード列を節ごとに切る(曲構成をカードの列へ展開する(曲構成, パターン一覧2))

        assert.equal(グループ列.length, 2)
        assert.equal(グループ列[0].カード列.length, 2)
        assert.deepEqual(グループ列[0].カード列.map((カード) => カード.位置.小節の番号), [0, 1])
        assert.equal(グループ列[1].カード列.length, 1)
    })
})
