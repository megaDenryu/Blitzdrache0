import type { 楽曲 } from '../../../../生成/編集資源契約.ts'
import type { カード位置, 曲構成のカード } from '../../編集モデル/index.ts'
import { カード列を節ごとに切る } from './カード列を節ごとに切る.ts'
import type { カード部品 } from './カード部品.ts'
import { 節の枠部品 } from './節の枠部品.ts'
import { 節の基準カード位置を求める } from './節の基準カード位置を求める.ts'
import { 節見出しの文言を組み立てる } from './節見出しの文言を組み立てる.ts'
import { 節の操作の押せるかを計算する } from './節の操作の押せるかを計算する.ts'
import type { 節の操作の種類 } from './節の操作の種類.ts'

// カードの列を節ごとに切り、見出しと操作の押せるかを添えて節の枠へ包む(タイムライン部品からの工程分離)。
// カード部品列はカード列と同じ順で1対1に並んでいる前提で、添字をずらしながら切り出す。
export function 節の枠一覧を組み立てる(
    楽曲: 楽曲,
    カード列: readonly 曲構成のカード[],
    カード部品列: readonly カード部品[],
    選択中のカード: カード位置 | null,
): readonly 節の枠部品[] {
    let 添字 = 0
    return カード列を節ごとに切る(カード列).map((グループ) => {
        const カード部品グループ = カード部品列.slice(添字, 添字 + グループ.カード列.length)
        添字 += グループ.カード列.length
        const 節 = 楽曲.曲構成[グループ.節の位置]
        if (節 === undefined) throw new Error(`カードの列が指す節が曲構成に無い: 節の位置=${グループ.節の位置}`)
        const 見出し = 節見出しの文言を組み立てる(グループ.パターンの名乗り, 節.繰り返し回数, 楽曲.パターン一覧)
        const 基準位置 = 節の基準カード位置を求める(グループ.先頭カードの位置, 選択中のカード)
        const 押せるか = 節の操作の押せるかを計算する(楽曲.曲構成, 基準位置)
        return new 節の枠部品(グループ.節の位置, 見出し, カード部品グループ, 押せるか)
    })
}

// 枠の先頭カードの位置を、操作の基準の解決に渡す形で節の枠一覧を配線する(組み立てに続く工程)。
export function 節の枠一覧を配線する(
    節の枠一覧: readonly 節の枠部品[],
    カード列: readonly 曲構成のカード[],
    on枠操作: (先頭カードの位置: カード位置, 種類: 節の操作の種類) => void,
): void {
    for (const 枠 of 節の枠一覧) {
        const 先頭カード = カード列.find((カード) => カード.位置.節の位置 === 枠.節の位置 && カード.位置.繰り返しの何回目 === 0)
        if (先頭カード === undefined) continue
        枠.配線する({ on操作: (種類) => on枠操作(先頭カード.位置, 種類) })
    }
}
