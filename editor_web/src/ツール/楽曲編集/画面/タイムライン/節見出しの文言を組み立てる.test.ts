import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { パターン } from '../../../../生成/編集資源契約.ts'
import { 節見出しの文言を組み立てる } from './節見出しの文言を組み立てる.ts'

function パターンを組み立てる(名乗り: string, 表示名: string): パターン {
    return { 名乗り, 表示名, 小節数: 2, 進行の参照: { 種類: '既定の進行', 識別子: 'C' }, 格子: [] }
}

describe('節見出しの文言を組み立てるテスト', () => {
    it('繰り返し回数が1のとき、表示名だけを返すこと', () => {
        const パターン一覧 = [パターンを組み立てる('a', 'A')]
        assert.equal(節見出しの文言を組み立てる('a', 1, パターン一覧), 'A')
    })

    it('繰り返し回数が2以上のとき、表示名の後ろへ「× 回数」を続けること', () => {
        const パターン一覧 = [パターンを組み立てる('a', 'A')]
        assert.equal(節見出しの文言を組み立てる('a', 4, パターン一覧), 'A × 4')
    })

    it('パターンが見つからないとき、名乗りをそのまま表示名の代わりに使うこと', () => {
        assert.equal(節見出しの文言を組み立てる('存在しない名乗り', 2, []), '存在しない名乗り × 2')
    })
})
