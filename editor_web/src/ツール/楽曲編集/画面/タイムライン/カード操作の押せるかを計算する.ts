import type { 曲の節 } from '../../../../生成/編集資源契約.ts'
import { カードの操作をコマンドへ写す } from '../../操作コマンド/index.ts'
import type { カード位置 } from '../../編集モデル/index.ts'
import type { カード操作の押せるか } from './カードの操作ボタン群.ts'

// カード1枚が持つ6つの操作を、実際にコマンドへ写して試し、押せるかどうかへ変換する。
// 押せない操作を押せる状態で出さないため、判定は実際の写しの結果に委ねる(自前で条件を再現しない)。
export function カード操作の押せるかを計算する(曲構成: readonly 曲の節[], 位置: カード位置): カード操作の押せるか {
    const 押せるか = (操作: Parameters<typeof カードの操作をコマンドへ写す>[1]): boolean =>
        カードの操作をコマンドへ写す(曲構成, 操作).種類 !== 'できない'

    return {
        前へ移動: 押せるか({ 種類: '前へ移動', 位置 }),
        前へ挿入: 押せるか({ 種類: '前へ挿入', 位置 }),
        複製: 押せるか({ 種類: '複製', 位置 }),
        削除: 押せるか({ 種類: '削除', 位置 }),
        後へ挿入: 押せるか({ 種類: '後へ挿入', 位置 }),
        後へ移動: 押せるか({ 種類: '後へ移動', 位置 }),
    }
}
