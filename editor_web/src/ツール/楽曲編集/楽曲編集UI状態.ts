import type { 楽曲 } from '../../生成/編集資源契約.ts'
import type { 打ち込みドラッグ見込み } from './画面/打ち込み見込み.ts'
import { 名乗りでパターンを探す, type カード位置, type 楽曲編集状態 } from './編集モデル/index.ts'
export type { 打ち込みドラッグ見込み } from './画面/打ち込み見込み.ts'

// 楽曲エディターのUIセッション状態。進行の外モードやドラッグ中の見込み、
// タイムラインで選択中のカードを保持する。保存にもコマンドにも入らない(設計正本の判断15)。
export class 楽曲編集UI状態 {
    public 進行の外モードか: boolean = false
    public ドラッグ見込み: 打ち込みドラッグ見込み | null = null
    public 選択中のカード: カード位置 | null = null

    // コマンドの適用・取り消し・読み込みのすべてが表示を再構築する前に通る唯一の入口
    // (`表示の同期.再構築する`)から呼ばれる。選択中のカードが残っていれば、格子が映す
    // パターンをそのカードのパターンへ合わせる。カードが失われていれば選択を外すだけにし、
    // 格子のパターンは変えない。取り消した操作の前の選択を復元する形は採らない(判断15)。
    public 選択とパターンを揃え直す(状態: 楽曲編集状態): void {
        this._選択中のカードが失われていたら外す(状態.楽曲)
        if (this.選択中のカード === null) return
        状態.選択中のカードのパターンへ選択中パターンを合わせる(this.選択中のカード)
    }

    // コマンドの適用で曲構成かパターンの小節数が変わり、選択中のカードが指す先が無くなったら未選択へ戻す。
    // 指す先は節・繰り返しの何回目・小節の番号の3つであり、小節の番号はその節が指すパターンの小節数で決まる。
    private _選択中のカードが失われていたら外す(楽曲: 楽曲): void {
        if (this.選択中のカード === null) return
        const 節 = 楽曲.曲構成[this.選択中のカード.節の位置]
        if (節 === undefined || this.選択中のカード.繰り返しの何回目 >= 節.繰り返し回数) {
            this.選択中のカード = null
            return
        }
        if (this.選択中のカード.小節の番号 >= 名乗りでパターンを探す(楽曲.パターン一覧, 節.パターンの名乗り).小節数) {
            this.選択中のカード = null
        }
    }
}

