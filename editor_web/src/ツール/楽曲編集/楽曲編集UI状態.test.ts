import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 新しいパターンの既定の小節数 } from '../../生成/編集資源契約.ts'
import { 初期楽曲を生成する, 楽曲編集状態 } from './編集モデル/index.ts'
import { 楽曲編集コマンドを適用する } from './操作コマンド/index.ts'
import { 楽曲編集UI状態 } from './楽曲編集UI状態.ts'

// 小節数2のパターンを1回繰り返す節を1つ持ち、その2小節目(小節の番号1)のカードを選んだ状態を作る。
function 二小節目を選んだ状態を作る(): { 状態: 楽曲編集状態; UI状態: 楽曲編集UI状態 } {
    const 状態 = new 楽曲編集状態(初期楽曲を生成する('song-1', '選択の確かめ'))
    楽曲編集コマンドを適用する(状態, { 種類: '曲の節を追加する', 値: { パターンの名乗り: 'pattern-1', 繰り返し回数: 1 } })
    const UI状態 = new 楽曲編集UI状態()
    UI状態.選択中のカード = { 節の位置: 0, 繰り返しの何回目: 0, 小節の番号: 1 }
    return { 状態, UI状態 }
}

// 「失われていたら外す」の判定はprivateであり、公開口の選択とパターンを揃え直すを通して確かめる。
describe('選択とパターンを揃え直す(カードが失われる側の判定)', () => {
    it('パターンの小節数を1へ減らすと、2小節目を指す選択を外す', () => {
        const { 状態, UI状態 } = 二小節目を選んだ状態を作る()
        楽曲編集コマンドを適用する(状態, { 種類: 'パターンの小節数を変える', 値: { 名乗り: 'pattern-1', 新しい小節数: 1 } })
        UI状態.選択とパターンを揃え直す(状態)
        assert.equal(UI状態.選択中のカード, null)
    })

    it('パターンの小節数を3へ増やしても、2小節目を指す選択は残す', () => {
        const { 状態, UI状態 } = 二小節目を選んだ状態を作る()
        楽曲編集コマンドを適用する(状態, { 種類: 'パターンの小節数を変える', 値: { 名乗り: 'pattern-1', 新しい小節数: 3 } })
        UI状態.選択とパターンを揃え直す(状態)
        assert.deepEqual(UI状態.選択中のカード, { 節の位置: 0, 繰り返しの何回目: 0, 小節の番号: 1 })
    })

    it('選択中の繰り返しの何回目が節の繰り返し回数に収まらなければ外す', () => {
        const { 状態, UI状態 } = 二小節目を選んだ状態を作る()
        UI状態.選択中のカード = { 節の位置: 0, 繰り返しの何回目: 1, 小節の番号: 0 }
        UI状態.選択とパターンを揃え直す(状態)
        assert.equal(UI状態.選択中のカード, null)
    })
})

// 曲構成パネルの節の変更とCtrl+Zの取り消しの両方が、この揃え直しを経由する(issue #188)。
describe('選択とパターンを揃え直す', () => {
    it('選択中のカードが残っていれば、格子が映すパターンをそのカードのパターンへ合わせる', () => {
        const 状態 = new 楽曲編集状態(初期楽曲を生成する('song-1', '選択の確かめ'))
        楽曲編集コマンドを適用する(状態, {
            種類: 'パターンを追加する',
            値: {
                名乗り: 'pattern-2',
                表示名: 'パターン2',
                小節数: 新しいパターンの既定の小節数,
                進行の参照: { 種類: '既定の進行', 識別子: '戦闘と道' },
            },
        })
        楽曲編集コマンドを適用する(状態, { 種類: '曲の節を追加する', 値: { パターンの名乗り: 'pattern-1', 繰り返し回数: 1 } })
        const UI状態 = new 楽曲編集UI状態()
        UI状態.選択中のカード = { 節の位置: 0, 繰り返しの何回目: 0, 小節の番号: 1 }

        // 曲構成パネルで節の指すパターンをpattern-2へ変える操作を模す。
        楽曲編集コマンドを適用する(状態, {
            種類: '曲の節を変える',
            値: { 節の位置: 0, 新しいパターンの名乗り: 'pattern-2', 新しい繰り返し回数: 1 },
        })
        UI状態.選択とパターンを揃え直す(状態)

        assert.deepEqual(UI状態.選択中のカード, { 節の位置: 0, 繰り返しの何回目: 0, 小節の番号: 1 })
        assert.equal(状態.選択中パターンの名乗り, 'pattern-2')
    })

    it('選択中のカードが失われていれば選択を外し、格子が映すパターンは変えない', () => {
        const { 状態, UI状態 } = 二小節目を選んだ状態を作る()
        状態.選択中パターンの名乗り = 'pattern-1'
        // パターンの小節数を1へ減らし、選択中の2小節目のカードを消す。
        楽曲編集コマンドを適用する(状態, { 種類: 'パターンの小節数を変える', 値: { 名乗り: 'pattern-1', 新しい小節数: 1 } })

        UI状態.選択とパターンを揃え直す(状態)

        assert.equal(UI状態.選択中のカード, null)
        assert.equal(状態.選択中パターンの名乗り, 'pattern-1')
    })
})
