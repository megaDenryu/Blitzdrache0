import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 楽曲入力一式を組む, 升目当たりを作る } from './楽曲の入力試験の下ごしらえ.ts'

const 左ボタン = 0
const 右ボタン = 2

describe('楽曲編集ポインタ振り分け', () => {
    it('同じ行を横ドラッグして離すと音を伸ばすコマンドが1つ積まれること', () => {
        const { 状態, UI状態, 操作, 振り分け } = 楽曲入力一式を組む()
        const パターン名 = 状態.選択中パターンを取得する().名乗り
        // トラック3は打楽器（全升目許可）
        const 起点 = 升目当たりを作る(パターン名, 3, 0, 0)
        const 途中 = 升目当たりを作る(パターン名, 3, 0, 1)
        const 終点 = 升目当たりを作る(パターン名, 3, 0, 2)

        assert.strictEqual(振り分け.押された(左ボタン, 起点), true)
        assert.strictEqual(操作.履歴件数, 0, 'ドラッグ開始時はコマンド未発行')
        assert.notStrictEqual(UI状態.ドラッグ見込み, null, '見込みが描かれていること')

        assert.strictEqual(振り分け.動かされた(途中), true)
        assert.strictEqual(操作.履歴件数, 0, 'ドラッグ途中はコマンド未発行')

        assert.strictEqual(振り分け.動かされた(終点), true)
        assert.strictEqual(操作.履歴件数, 0, 'ドラッグ途中はコマンド未発行')

        振り分け.離された(左ボタン)
        assert.strictEqual(操作.履歴件数, 1, '離した時点で1つのコマンドが積まれる')
        assert.strictEqual(UI状態.ドラッグ見込み, null, '見込みが消えていること')

        const 行 = 状態.選択中パターンを取得する().格子[3]?.行一覧[0]
        assert.deepStrictEqual(行?.slice(0, 4), [1, 2, 2, 0], '始まり1つ・継続2つで伸びていること')
    })

    it('違う行へ移ったときにその行へ打点を置くが1つ積まれること', () => {
        const { 状態, 操作, 振り分け } = 楽曲入力一式を組む()
        const パターン名 = 状態.選択中パターンを取得する().名乗り
        const 起点 = 升目当たりを作る(パターン名, 3, 0, 0)
        const 移り先 = 升目当たりを作る(パターン名, 3, 1, 3)

        assert.strictEqual(振り分け.押された(左ボタン, 起点), true)
        assert.strictEqual(振り分け.動かされた(移り先), true)
        振り分け.離された(左ボタン)

        assert.strictEqual(操作.履歴件数, 1)
        const 行0 = 状態.選択中パターンを取得する().格子[3]?.行一覧[0]
        const 行1 = 状態.選択中パターンを取得する().格子[3]?.行一覧[1]
        assert.strictEqual(行0?.[0], 0, '起点の行には音が入らないこと')
        assert.strictEqual(行1?.[3], 1, '移り先の行に打点が置かれること')
    })

    it('右ボタンドラッグで範囲の打点を消すが1つ積まれること', () => {
        const { 状態, 操作, 振り分け } = 楽曲入力一式を組む()
        const パターン名 = 状態.選択中パターンを取得する().名乗り
        // 事前に音を置く
        const 起点 = 升目当たりを作る(パターン名, 3, 0, 0)
        const 終点 = 升目当たりを作る(パターン名, 3, 0, 2)
        振り分け.押された(左ボタン, 起点)
        振り分け.動かされた(終点)
        振り分け.離された(左ボタン)
        assert.strictEqual(操作.履歴件数, 1)

        // 右ボタンで消すドラッグ
        assert.strictEqual(振り分け.押された(右ボタン, 起点), true)
        assert.strictEqual(振り分け.動かされた(終点), true)
        振り分け.離された(右ボタン)

        assert.strictEqual(操作.履歴件数, 2)
        const 行 = 状態.選択中パターンを取得する().格子[3]?.行一覧[0]
        assert.deepStrictEqual(行?.slice(0, 4), [0, 0, 0, 0], '範囲が消去されていること')
    })

    it('和音が許さない升目は通常モードでは押せず進行の外モードでは置けること', () => {
        const { 状態, UI状態, 操作, 振り分け } = 楽曲入力一式を組む()
        const パターン名 = 状態.選択中パターンを取得する().名乗り
        // トラック0の行でステップ0のAm和音（A, C, E）で許されない音（例えば行位置でピッチクラスがFやD#など）を探す
        const トラック0 = 状態.楽曲.トラック構成[0]
        assert.ok(トラック0 && トラック0.音の並び.種類 === '音高の行一覧')
        const 不許可行 = トラック0.音の並び.値.findIndex((p) => ![9, 0, 4].includes(((p % 12) + 12) % 12))
        assert.ok(不許可行 >= 0, '不許可の行が存在すること')

        const 当たり = 升目当たりを作る(パターン名, 0, 不許可行, 0)

        // 通常モードでは押せない
        assert.strictEqual(振り分け.押された(左ボタン, 当たり), false)
        assert.strictEqual(操作.履歴件数, 0)

        // 進行の外モードに切り替える
        UI状態.進行の外モードか = true
        assert.strictEqual(振り分け.押された(左ボタン, 当たり), true)
        振り分け.離された(左ボタン)

        assert.strictEqual(操作.履歴件数, 1)
        const 行 = 状態.選択中パターンを取得する().格子[0]?.行一覧[不許可行]
        assert.strictEqual(行?.[0], 3, '進行の外の打点(値3)として記録されること')
    })

    it('取り消しで格子が元に戻ること', () => {
        const { 状態, 操作, 振り分け } = 楽曲入力一式を組む()
        const パターン名 = 状態.選択中パターンを取得する().名乗り
        const 起点 = 升目当たりを作る(パターン名, 3, 0, 0)

        振り分け.押された(左ボタン, 起点)
        振り分け.離された(左ボタン)
        assert.strictEqual(状態.選択中パターンを取得する().格子[3]?.行一覧[0]?.[0], 1)

        assert.strictEqual(操作.直前の操作を取り消す(), true)
        assert.strictEqual(状態.選択中パターンを取得する().格子[3]?.行一覧[0]?.[0], 0, '元に戻ること')
    })
})
