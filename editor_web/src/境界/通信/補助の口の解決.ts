import type { 建物の格子, 建物の格子の一覧項目, 建物外形カタログ } from '../../生成/編集資源契約.ts'
import type { 建物定義ID } from '../建物定義ID.ts'
import type { 読込結果, 保存結果 } from './サーバー通信結果.ts'
import { 建物外形カタログ接続か, 建物外形カタログを提供しない失敗, type 建物外形カタログ接続 } from './建物外形カタログ接続.ts'
import {
    建物の格子を提供しない保存失敗,
    建物の格子を提供しない読込失敗,
    建物の格子接続か,
    type 建物の格子接続,
} from './建物の格子接続.ts'

// 保管庫の接続が持たないことのある補助の口(建物外形カタログ・建物の格子)を1つにまとめた口。
export type 補助の口 = 建物外形カタログ接続 & 建物の格子接続

// 口を持たない接続を包んだときに使う代替。`Option`で不在を全消費者へ波及させず、
// 使った時点で明示の失敗を返す(グローバルCLAUDE.md「使用不可はNull Objectで表す」)。
class 補助の口を持たない接続 implements 補助の口 {
    public 建物外形カタログを読む(): Promise<読込結果<建物外形カタログ>> {
        return Promise.resolve(建物外形カタログを提供しない失敗())
    }

    public 建物一覧を読む(): Promise<読込結果<建物の格子の一覧項目[]>> {
        return Promise.resolve(建物の格子を提供しない読込失敗<建物の格子の一覧項目[]>())
    }

    public 建物の格子を読む(): Promise<読込結果<建物の格子>> {
        return Promise.resolve(建物の格子を提供しない読込失敗<建物の格子>())
    }

    public 建物の格子を保存する(): Promise<保存結果> {
        return Promise.resolve(建物の格子を提供しない保存失敗())
    }
}

// 内側の接続が両方の口を持つならそれを、片方でも欠けるなら代替を返す。片方だけを本物にしないのは、
// 「カタログは読めるが格子は読めない」という半端な組み合わせが画面の失敗の説明を分かりにくくするためである。
export function 補助の口を解決する(内側: object): 補助の口 {
    if (建物外形カタログ接続か(内側) && 建物の格子接続か(内側)) {
        return 補助の口として束ねる(内側)
    }
    return new 補助の口を持たない接続()
}

function 補助の口として束ねる(内側: 建物外形カタログ接続 & 建物の格子接続): 補助の口 {
    return {
        建物外形カタログを読む: () => 内側.建物外形カタログを読む(),
        建物一覧を読む: () => 内側.建物一覧を読む(),
        建物の格子を読む: (建物定義ID: 建物定義ID) => 内側.建物の格子を読む(建物定義ID),
        建物の格子を保存する: (格子: 建物の格子) => 内側.建物の格子を保存する(格子),
    }
}
