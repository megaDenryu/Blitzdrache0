import type { 建物の格子, 建物の格子の一覧項目, 建物外形カタログ, 楽曲 } from '../../生成/編集資源契約.ts'
import type { 建物定義ID } from '../建物定義ID.ts'
import type { 楽曲ID } from '../楽曲ID.ts'
import type { 読込結果, 保存結果 } from './サーバー通信結果.ts'
import { 建物外形カタログ接続か, 建物外形カタログを提供しない失敗, type 建物外形カタログ接続 } from './建物外形カタログ接続.ts'
import {
    建物の格子を提供しない保存失敗,
    建物の格子を提供しない読込失敗,
    建物の格子接続か,
    type 建物の格子接続,
} from './建物の格子接続.ts'
import {
    楽曲を提供しない保存失敗,
    楽曲を提供しない読込失敗,
    楽曲接続か,
    type 楽曲接続,
} from './楽曲接続.ts'

// 保管庫の接続が持たないことのある補助の口(建物外形カタログ・建物の格子・楽曲)を1つにまとめた口。
export type 補助の口 = 建物外形カタログ接続 & 建物の格子接続 & 楽曲接続

// 口を持たない接続を包んだときに使う代替。
class 補助の口を持たない接続 implements 補助の口 {
    public 建物外形カタログを読む(): Promise<読込結果<建物外形カタログ>> {
        return Promise.resolve(建物外形カタログを提供しない失敗())
    }

    public 建物一覧を読む(): Promise<読込結果<建物の格子の一覧項目[]>> {
        return Promise.resolve(建物の格子を提供しない読込失敗<建物の格子の一覧項目[]>())
    }

    public 建物の格子を読む(): Promise<読込結果<建物の格子>> {
        return Promise.resolve(建物の格子を提供しない読込失敗<建物の格子>())
    }

    public 建物の格子を保存する(): Promise<保存結果> {
        return Promise.resolve(建物の格子を提供しない保存失敗())
    }

    public 楽曲一覧を読む(): Promise<読込結果<楽曲ID[]>> {
        return Promise.resolve(楽曲を提供しない読込失敗<楽曲ID[]>())
    }

    public 楽曲を読む(): Promise<読込結果<楽曲>> {
        return Promise.resolve(楽曲を提供しない読込失敗<楽曲>())
    }

    public 楽曲を保存する(): Promise<保存結果> {
        return Promise.resolve(楽曲を提供しない保存失敗())
    }
}

export function 補助の口を解決する(内側: object): 補助の口 {
    if (建物外形カタログ接続か(内側) && 建物の格子接続か(内側) && 楽曲接続か(内側)) {
        return 補助の口として束ねる(内側)
    }
    return new 補助の口を持たない接続()
}

function 補助の口として束ねる(内側: 建物外形カタログ接続 & 建物の格子接続 & 楽曲接続): 補助の口 {
    return {
        建物外形カタログを読む: () => 内側.建物外形カタログを読む(),
        建物一覧を読む: () => 内側.建物一覧を読む(),
        建物の格子を読む: (建物定義ID: 建物定義ID) => 内側.建物の格子を読む(建物定義ID),
        建物の格子を保存する: (格子: 建物の格子) => 内側.建物の格子を保存する(格子),
        楽曲一覧を読む: () => 内側.楽曲一覧を読む(),
        楽曲を読む: (楽曲ID: 楽曲ID) => 内側.楽曲を読む(楽曲ID),
        楽曲を保存する: (楽曲: 楽曲) => 内側.楽曲を保存する(楽曲),
    }
}

