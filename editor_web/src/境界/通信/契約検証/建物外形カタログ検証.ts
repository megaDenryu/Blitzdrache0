import type { 建物外形カタログ, 建物外形定義 } from '../../../生成/編集資源契約.ts'
import { 配列か, 数値か, オブジェクトか, 文字列か } from './オブジェクト判定.ts'

export function 建物外形カタログの形か(値: unknown): 値 is 建物外形カタログ {
    return オブジェクトか(値)
        && 値['形式版'] === 1
        && 配列か(値['建物定義一覧'])
        && 値['建物定義一覧'].every(建物外形定義の形か)
}

function 建物外形定義の形か(値: unknown): 値 is 建物外形定義 {
    if (!オブジェクトか(値) || !オブジェクトか(値['ベイ']) || !オブジェクトか(値['入口のローカル方向']) || !オブジェクトか(値['外接箱'])) return false
    const 箱 = 値['外接箱']
    return 文字列か(値['識別子'])
        && 文字列か(値['表示名'])
        && (値['用途'] === '骨格見本' || 値['用途'] === '家屋')
        && 配列か(値['部品の識別子一覧'])
        && 値['部品の識別子一覧'].every(文字列か)
        && 数値か(値['ベイ']['横']) && 数値か(値['ベイ']['奥']) && 数値か(値['ベイ']['階'])
        && 数値か(値['高さメートル'])
        && 数値か(値['入口のローカル方向']['x']) && 数値か(値['入口のローカル方向']['z'])
        && 数値三つ組か(箱['最小']) && 数値三つ組か(箱['最大'])
}

function 数値三つ組か(値: unknown): 値 is [number, number, number] {
    return 配列か(値) && 値.length === 3 && 値.every(数値か)
}
