import { 建物の格子の形式版, type はめ口の値, type 建物の格子, type 升目の宣言 } from '../../../生成/編集資源契約.ts'
import { オブジェクトか, 数値か, 文字列か, 配列か } from './オブジェクト判定.ts'

export function 建物の格子の形か(値: unknown): 値 is 建物の格子 {
    if (!オブジェクトか(値) || !オブジェクトか(値['入口のローカル方向']) || !オブジェクトか(値['格子'])) return false
    const 格子 = 値['格子']
    return 値['形式版'] === 建物の格子の形式版
        && 文字列か(値['建物定義ID'])
        && 文字列か(値['表示名'])
        && 数値か(値['入口のローカル方向']['x'])
        && 数値か(値['入口のローカル方向']['z'])
        && 升目の座標の形か(格子['根の升目'])
        && 配列か(格子['升目一覧'])
        && 格子['升目一覧'].every(升目の宣言の形か)
        && オブジェクトか(値['装飾'])
}

export function 建物の格子の一覧の形か(値: unknown): 値 is { 識別子: string; 表示名: string; 升目の数: number }[] {
    return 配列か(値)
        && 値.every((項目) => オブジェクトか(項目) && 文字列か(項目['識別子']) && 文字列か(項目['表示名']) && 数値か(項目['升目の数']))
}

function 升目の座標の形か(値: unknown): boolean {
    return オブジェクトか(値) && 数値か(値['横']) && 数値か(値['奥']) && 数値か(値['階'])
}

function 升目の宣言の形か(値: unknown): 値 is 升目の宣言 {
    if (!オブジェクトか(値) || !升目の座標の形か(値['座標'])) return false
    return はめ口の形か(値['正面'])
        && はめ口の形か(値['背面'])
        && はめ口の形か(値['左面'])
        && はめ口の形か(値['右面'])
        && (値['床'] === '張らない' || 値['床'] === '張る')
        && (値['屋根'] === '載せない' || 値['屋根'] === '載せる')
}

function はめ口の形か(値: unknown): 値 is はめ口の値 {
    if (!オブジェクトか(値)) return false
    if (値['種類'] === '入れない') return true
    if (値['種類'] !== '壁を入れる' || !オブジェクトか(値['値'])) return false
    const 中身 = 値['値']
    return 壁の種類か(中身['壁の種類']) && オブジェクトか(中身['外面の飾り']) && 文字列か(中身['外面の飾り']['種類'])
}

function 壁の種類か(値: unknown): boolean {
    return 値 === '平壁' || 値 === '窓壁' || 値 === '扉枠付きの壁'
}
