import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 大域世界構造の形か } from './大域世界構造検証.ts'
import { チャンク構造の形か } from './チャンク構造検証.ts'

// 型ガードの戻り値は「値 is 型」であり、中身が契約とずれていてもTypeScriptは気付けない。
// 受信した形を実際に通して確かめるこの試験だけが、ずれを機械で止められる。
// 道路が一覧になったとき、ここを直し忘れて保存済みの世界が丸ごと拒まれ、
// 起動時の例外が握り潰されて初期生成の世界へ差し替わった。その再発をここで止める。

const 区画割り = { 一辺のメートル: 1024, 軸あたりチャンク数: 4, チャンクあたり格子解像度: 128 }
const 広域道路 = { 制御点列: [{ x: 1, y: 2, z: 3 }], 全幅メートル: 12, 細分割数: 120 }
const チャンクの道路 = { 制御点列: [], 全幅メートル: 8, 散布除外バッファメートル: 14, 細分割数: 80 }
const 散布 = { 最小間隔メートル: 5.5, 乱数の種: 42n }

describe('受信した大域世界構造の形の検査', () => {
    it('サーバーが返す広域道路一覧の形を受理すること', () => {
        assert.ok(大域世界構造の形か({ 区画割り, 広域道路一覧: [広域道路] }))
    })

    it('道路が1本も無い一覧も受理すること', () => {
        assert.ok(大域世界構造の形か({ 区画割り, 広域道路一覧: [] }))
    })

    it('広域道路が単数だった頃の形は受理しないこと', () => {
        assert.ok(!大域世界構造の形か({ 区画割り, 広域道路 }))
    })

    it('一覧の中身が広域道路の形でなければ受理しないこと', () => {
        assert.ok(!大域世界構造の形か({ 区画割り, 広域道路一覧: [{ 制御点列: [] }] }))
    })
})

describe('受信したチャンク構造の形の検査', () => {
    it('サーバーが返す道路一覧の形を受理すること', () => {
        assert.ok(チャンク構造の形か({ 道路一覧: [チャンクの道路], 建物一覧: [], 散布 }))
    })

    it('道路が1本も無い一覧も受理すること', () => {
        assert.ok(チャンク構造の形か({ 道路一覧: [], 建物一覧: [], 散布 }))
    })

    it('道路が単数だった頃の形は受理しないこと', () => {
        assert.ok(!チャンク構造の形か({ 道路: チャンクの道路, 建物一覧: [], 散布 }))
    })

    it('一覧の中身がチャンクの道路の形でなければ受理しないこと', () => {
        assert.ok(!チャンク構造の形か({ 道路一覧: [{ 制御点列: [] }], 建物一覧: [], 散布 }))
    })
})
