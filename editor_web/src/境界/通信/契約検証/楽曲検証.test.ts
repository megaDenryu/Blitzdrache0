import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import type { 楽曲 } from '../../../生成/編集資源契約.ts'
import { 楽曲の形式版 } from '../../../生成/編集資源契約.ts'
import { 楽曲の形か, 楽曲一覧の形か } from './楽曲検証.ts'

const テスト楽曲: 楽曲 = {
    形式版: 楽曲の形式版,
    名乗り: 'song-1',
    表示名: 'テスト楽曲',
    拍毎分: 124,
    トラック構成: [
        {
            表示名: '旋律',
            種類: '旋律',
            音の並び: { 種類: '音高の行一覧', 値: [60, 62, 64] },
            楽器: 'グランドピアノ',
            音量: 0.8,
            進行の割り当て: null,
        },
    ],
    ミキサー設定: { 全体の音量: 0.8, 残響の量: 0.2, 遅延の量: 0.1, 遅延のステップ数: 4 },
    独自進行一覧: [],
    パターン一覧: [
        {
            名乗り: 'pattern-1',
            表示名: 'パターン1',
            進行の参照: { 種類: '既定の進行', 識別子: '戦闘と道' },
            格子: [{ 行一覧: [[0, 0, 0], [0, 0, 0], [0, 0, 0]] }],
        },
    ],
    曲構成: [{ パターンの名乗り: 'pattern-1', 繰り返し回数: 2 }],
}

describe('受信した楽曲データの形の検査', () => {
    it('正常な楽曲の形を受理すること', () => {
        assert.ok(楽曲の形か(テスト楽曲))
    })

    it('楽曲一覧の文字列配列を受理すること', () => {
        assert.ok(楽曲一覧の形か(['song-1', 'song-2']))
        assert.ok(楽曲一覧の形か([]))
    })

    it('文字列以外の要素を含む一覧は受理しないこと', () => {
        assert.ok(!楽曲一覧の形か(['song-1', 123]))
        assert.ok(!楽曲一覧の形か(null))
    })

    it('形式版が異なる楽曲は受理しないこと', () => {
        const 不正 = { ...テスト楽曲, 形式版: 999 }
        assert.ok(!楽曲の形か(不正))
    })

    it('トラック構成が欠けている楽曲は受理しないこと', () => {
        const 不正 = { ...テスト楽曲, トラック構成: null }
        assert.ok(!楽曲の形か(不正))
    })
})
