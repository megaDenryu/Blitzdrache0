import type { トラック定義, 音の並び, トラックの種類, 楽器, 打楽器の種類 } from '../../../生成/編集資源契約.ts'
import { オブジェクトか, 数値か, 文字列か, 配列か } from './オブジェクト判定.ts'
import { コード進行参照の形か } from './コード進行検証.ts'

export function トラック定義の形か(値: unknown): 値 is トラック定義 {
    if (!オブジェクトか(値)) return false
    const 進行の割り当て値 = 値['進行の割り当て']
    const 進行の割り当て妥当 = 進行の割り当て値 === null || コード進行参照の形か(進行の割り当て値)
    return 文字列か(値['表示名'])
        && トラックの種類か(値['種類'])
        && 音の並びの形か(値['音の並び'])
        && 楽器か(値['楽器'])
        && 数値か(値['音量'])
        && 進行の割り当て妥当
}

export function トラックの種類か(値: unknown): 値 is トラックの種類 {
    return 値 === '旋律' || 値 === '伴奏' || 値 === '低音' || 値 === '打楽器'
}

export function 楽器か(値: unknown): 値 is 楽器 {
    return 値 === 'グランドピアノ'
        || 値 === '弦楽合奏'
        || 値 === 'フルート'
        || 値 === '矩形波の主旋律'
        || 値 === 'アコースティックギター'
        || 値 === 'エレクトリックピアノ'
        || 値 === 'ウッドベース'
        || 値 === 'エレキベース'
        || 値 === '三角波のベース'
        || 値 === '生ドラム'
        || 値 === '矩形波と雑音のドラム'
}

export function 打楽器の種類か(値: unknown): 値 is 打楽器の種類 {
    return 値 === 'バスドラム' || 値 === 'スネア' || 値 === 'ハイハット'
}

export function 音の並びの形か(値: unknown): 値 is 音の並び {
    if (!オブジェクトか(値)) return false
    if (値['種類'] === '音高の行一覧') {
        return 配列か(値['値']) && 値['値'].every(数値か)
    }
    if (値['種類'] === '打楽器の行一覧') {
        return 配列か(値['値']) && 値['値'].every(打楽器の種類か)
    }
    return false
}
