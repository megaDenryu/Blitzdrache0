import { 楽曲の形式版, type 楽曲, type ミキサー設定 } from '../../../生成/編集資源契約.ts'
import { オブジェクトか, 数値か, 文字列か, 配列か } from './オブジェクト判定.ts'
import { コード進行の形か } from './コード進行検証.ts'
import { トラック定義の形か } from './楽曲トラック検証.ts'
import { パターンの形か, 曲の節の形か } from './楽曲パターン検証.ts'

export * from './コード進行検証.ts'
export * from './楽曲トラック検証.ts'
export * from './楽曲パターン検証.ts'

export function 楽曲一覧の形か(値: unknown): 値 is string[] {
    return 配列か(値) && 値.every((項目) => 文字列か(項目))
}

export function 楽曲の形か(値: unknown): 値 is 楽曲 {
    if (!オブジェクトか(値)) return false
    return 値['形式版'] === 楽曲の形式版
        && 文字列か(値['名乗り'])
        && 文字列か(値['表示名'])
        && 数値か(値['拍毎分'])
        && 配列か(値['トラック構成'])
        && 値['トラック構成'].every(トラック定義の形か)
        && ミキサー設定の形か(値['ミキサー設定'])
        && 配列か(値['独自進行一覧'])
        && 値['独自進行一覧'].every(コード進行の形か)
        && 配列か(値['パターン一覧'])
        && 値['パターン一覧'].every(パターンの形か)
        && 配列か(値['曲構成'])
        && 値['曲構成'].every(曲の節の形か)
}

export function ミキサー設定の形か(値: unknown): 値 is ミキサー設定 {
    if (!オブジェクトか(値)) return false
    return 数値か(値['全体の音量'])
        && 数値か(値['残響の量'])
        && 数値か(値['遅延の量'])
        && 数値か(値['遅延のステップ数'])
}
