import type { 建物の格子, 建物の格子の一覧項目 } from '../../生成/編集資源契約.ts'
import type { 建物定義ID } from '../建物定義ID.ts'
import type { 読込結果, 保存結果 } from './サーバー通信結果.ts'

// 建物エディターが編集する格子を読み書きする境界。保存の受理はサーバーが決め、
// 変換できない格子は正本を書き換えずに拒まれる(判断2の保存規律)。
export interface 建物の格子接続 {
    建物一覧を読む(): Promise<読込結果<建物の格子の一覧項目[]>>
    建物の格子を読む(建物定義ID: 建物定義ID): Promise<読込結果<建物の格子>>
    建物の格子を保存する(格子: 建物の格子): Promise<保存結果>
}

export function 建物の格子接続か(値: object): 値 is 建物の格子接続 {
    return '建物の格子を保存する' in 値 && typeof 値.建物の格子を保存する === 'function'
}

// 格子の口を持たない接続へ包んだときの失敗。無言で「無し」を返すと、建物を編集できない理由が
// 画面のどこにも出ないため、明示の失敗として返す。
export function 建物の格子を提供しない読込失敗<結果>(): 読込結果<結果> {
    return { 種別: '失敗', エラー: { 種別: '未対応', 説明: 'この接続は建物の格子を提供しない' } }
}

export function 建物の格子を提供しない保存失敗(): 保存結果 {
    return { 種別: '失敗', エラー: { 種別: '未対応', 説明: 'この接続は建物の格子を提供しない' } }
}
