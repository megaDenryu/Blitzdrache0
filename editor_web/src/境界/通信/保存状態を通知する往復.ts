import type { 大域世界構造, チャンク座標, チャンク構造, 建物外形カタログ } from '../../生成/編集資源契約.ts'
import type { 読込結果, 保存結果 } from './サーバー通信結果.ts'
import type { プロジェクト保管庫接続 } from './プロジェクト保管庫接続.ts'
import type { 保存状態サービス } from './保存状態サービス.ts'
import type { 補助の口 } from './補助の口の解決.ts'
import { 保存結果から保存状態を作る, 読込結果から保存状態を作る } from './通信結果から保存状態を作る.ts'

// 内側の保管庫と通知の宛先を保持し、成否を保存状態サービスへ伝えながら往復するメソッドを公開する操作サービス。
// 通知の要る往復だけをここへ集めるのは、素通しの往復(高さ格子・材質重み・マテリアル台帳)と
// 呼び出しの形が違うためである。素通しの側は包む理由が無く、そのまま内側へ委ねる。
export class 保存状態を通知する往復 {
    public constructor(
        private readonly _内側保管庫: プロジェクト保管庫接続,
        private readonly _補助の口: 補助の口,
        private readonly _通知: 保存状態サービス,
    ) {}

    public async 大域世界の構造を読む(): Promise<読込結果<大域世界構造>> {
        const 結果 = await this._内側保管庫.大域世界の構造を読む()
        const 状態 = 読込結果から保存状態を作る(結果)
        this._通知.大域状態を更新する(状態.文言, 状態.エラーか)
        return 結果
    }

    public async 大域世界の構造を保存する(構造: 大域世界構造): Promise<保存結果> {
        const 結果 = await this._内側保管庫.大域世界の構造を保存する(構造)
        const 状態 = 保存結果から保存状態を作る(結果)
        this._通知.大域状態を更新する(状態.文言, 状態.エラーか)
        return 結果
    }

    public async チャンクの構造を読む(座標: チャンク座標): Promise<読込結果<チャンク構造>> {
        const 結果 = await this._内側保管庫.チャンクの構造を読む(座標)
        const 状態 = 読込結果から保存状態を作る(結果)
        this._通知.チャンク状態を更新する(座標, 状態.文言, 状態.エラーか)
        return 結果
    }

    public async チャンクの構造を保存する(座標: チャンク座標, 構造: チャンク構造): Promise<保存結果> {
        const 結果 = await this._内側保管庫.チャンクの構造を保存する(座標, 構造)
        const 状態 = 保存結果から保存状態を作る(結果)
        this._通知.チャンク状態を更新する(座標, 状態.文言, 状態.エラーか)
        return 結果
    }

    // カタログが読めないと建物を1件も置けない。理由を大域の保存状態へ出し、無言で空のカタログにしない。
    public async 建物外形カタログを読む(): Promise<読込結果<建物外形カタログ>> {
        const 結果 = await this._補助の口.建物外形カタログを読む()
        if (結果.種別 === '失敗') {
            this._通知.大域状態を更新する(`建物外形カタログ読込失敗: ${結果.エラー.種別} ${結果.エラー.説明}`, true)
        }
        return 結果
    }
}
