import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import type { チャンク構造 } from '../../生成/編集資源契約.ts'
import { チャンク構造をJSON文字列へ直列化する, JSON文字列からチャンク構造を復元する } from './チャンク構造直列化.ts'
import { チャンク構造の形か } from './契約検証/チャンク構造検証.ts'

describe('チャンク構造のbigint乱数の種往復テスト', () => {
    it('2^53を超えるu64乱数の種が1ビットも落ちずにJSON文字列とBigInt間で往復すること', () => {
        const テスト用種一覧: bigint[] = [
            0n,
            12345n,
            9007199254740993n, // 2^53 + 1 (JS Numberの最大安全整数を超える値)
            9223372036854775807n, // 2^63 - 1 (i64最大値)
            18446744073709551615n, // 2^64 - 1 (u64最大値)
        ]

        for (const 種 of テスト用種一覧) {
            const 元データ: チャンク構造 = {
                道路: {
                    制御点列: [{ x: 10, y: 5, z: 20 }],
                    全幅メートル: 8.0,
                    散布除外バッファメートル: 14.0,
                    細分割数: 80,
                },
                建物一覧: [
                    {
                        識別子: '家屋_1',
                        種別: '家屋',
                        位置: { x: 1, y: 2, z: 3 },
                        向きラジアン: 0.5,
                        基礎半径メートル: 6.0,
                        なじみ半径メートル: 12.0,
                    },
                ],
                散布: {
                    最小間隔メートル: 5.5,
                    乱数の種: 種,
                },
            }

            const json文字列 = チャンク構造をJSON文字列へ直列化する(元データ)

            // JSON文字列内で乱数の種が引用符なしの生数値リテラルになっていること
            assert.ok(
                json文字列.includes(`"乱数の種":${種.toString()}`) ||
                json文字列.includes(`"乱数の種": ${種.toString()}`),
                `JSON文字列に乱数の種が数値リテラルとして埋め込まれていること: ${json文字列}`,
            )

            const 復元オブジェクト = JSON文字列からチャンク構造を復元する(json文字列)
            assert.ok(チャンク構造の形か(復元オブジェクト), '復元結果がチャンク構造型ガードを満たすこと')

            assert.strictEqual(
                復元オブジェクト.散布.乱数の種,
                種,
                `乱数の種が1ビットも落ちずに一致すること: 期待=${種}, 実際=${復元オブジェクト.散布.乱数の種}`,
            )
            assert.deepStrictEqual(復元オブジェクト, 元データ, '構造全体が完全に一致すること')
        }
    })
})
