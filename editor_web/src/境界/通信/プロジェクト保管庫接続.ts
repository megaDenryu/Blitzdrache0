import type { 大域世界構造, チャンク座標, チャンク構造, マテリアル台帳 } from '../../生成/編集資源契約.ts'
import type { 読込結果, 保存結果 } from './サーバー通信結果.ts'

// エディターサーバーまたはローカル保管庫との通信を差し替え可能にする永続化境界。
// コンポジションルートが実サーバー接続を注入する。
// 参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断2」
export interface プロジェクト保管庫接続 {
    大域世界の構造を読む(): Promise<読込結果<大域世界構造>>
    大域世界の構造を保存する(構造: 大域世界構造): Promise<保存結果>

    大域世界の高さ格子を読む(): Promise<読込結果<ArrayBufferLike>>
    大域世界の高さ格子を保存する(バイト列: ArrayBufferLike): Promise<保存結果>

    チャンクの構造を読む(座標: チャンク座標): Promise<読込結果<チャンク構造>>
    チャンクの構造を保存する(座標: チャンク座標, 構造: チャンク構造): Promise<保存結果>

    チャンクの高さ格子を読む(座標: チャンク座標): Promise<読込結果<ArrayBufferLike>>
    チャンクの高さ格子を保存する(座標: チャンク座標, バイト列: ArrayBufferLike): Promise<保存結果>

    チャンクの材質重みを読む(座標: チャンク座標): Promise<読込結果<ArrayBufferLike>>
    チャンクの材質重みを保存する(座標: チャンク座標, バイト列: ArrayBufferLike): Promise<保存結果>

    マテリアル台帳を読む(): Promise<読込結果<マテリアル台帳>>
    マテリアル台帳を保存する(台帳: マテリアル台帳): Promise<保存結果>
}
