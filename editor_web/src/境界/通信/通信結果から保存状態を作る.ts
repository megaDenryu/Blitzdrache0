import type { 保存状態情報 } from './保存状態サービス.ts'
import type { 読込結果, 保存結果 } from './サーバー通信結果.ts'

// 通信結果を、保存状態サービスへ流す文言と成否へ写す純粋関数。大域とチャンクで同じ文言を使うため、
// 対象ごとに書き分けず1箇所へ置く。
export function 読込結果から保存状態を作る<値>(結果: 読込結果<値>): 保存状態情報 {
    if (結果.種別 === '成功') return { 文言: '読込完了(起動時)', エラーか: false }
    if (結果.種別 === '無し') return { 文言: '未保存(初期生成)', エラーか: false }
    return { 文言: `読込失敗: ${結果.エラー.種別} ${結果.エラー.説明}`, エラーか: true }
}

export function 保存結果から保存状態を作る(結果: 保存結果): 保存状態情報 {
    if (結果.種別 === '成功') return { 文言: '保存完了', エラーか: false }
    return { 文言: `保存失敗: ${結果.エラー.種別} ${結果.エラー.説明}`, エラーか: true }
}
