import type { 世界の区画割り } from '../生成/編集資源契約.ts'
import type { プロジェクト保管庫接続 } from '../境界/通信/index.ts'
import type { ワールド編集状態 } from '../ツール/チャンク編集/編集モデル/index.ts'

// ワールド編集状態の資源（大域世界構造の整合確認および登録済みチャンク）を保管庫へ検証付きで保存する。
// 大域世界の高さ格子・広域道路は大域世界の正本であり、チャンクの保存では一切書かない。
export async function ワールド状態を保存する(
    保管庫: プロジェクト保管庫接続,
    状態: ワールド編集状態,
): Promise<void> {
    const 大域構造結果 = await 保管庫.大域世界の構造を読む()
    if (大域構造結果.種別 === '失敗') {
        throw new Error(`大域世界構造の読込失敗: ${大域構造結果.エラー.種別} ${大域構造結果.エラー.説明}`)
    }

    if (大域構造結果.種別 === '無し') {
        const 大域構造保存 = await 保管庫.大域世界の構造を保存する(状態.大域世界構造)
        if (大域構造保存.種別 === '失敗') {
            throw new Error(`大域世界構造の保存失敗: ${大域構造保存.エラー.種別} ${大域構造保存.エラー.説明}`)
        }
    } else {
        区画割りの整合を確認する(大域構造結果.値.区画割り, 状態.大域世界構造.区画割り)
    }

    for (const [, チャンク] of 状態.チャンク一覧マップ) {
        const 構造結果 = await 保管庫.チャンクの構造を保存する(チャンク.座標, チャンク.構造を取得する())
        if (構造結果.種別 === '失敗') {
            throw new Error(`チャンク(${チャンク.座標.x},${チャンク.座標.z})構造の保存失敗: ${構造結果.エラー.種別} ${構造結果.エラー.説明}`)
        }

        const 高さ結果 = await 保管庫.チャンクの高さ格子を保存する(チャンク.座標, チャンク.高さ場.格子データ.buffer)
        if (高さ結果.種別 === '失敗') {
            throw new Error(`チャンク(${チャンク.座標.x},${チャンク.座標.z})高さ格子の保存失敗: ${高さ結果.エラー.種別} ${高さ結果.エラー.説明}`)
        }

        const 材質結果 = await 保管庫.チャンクの材質重みを保存する(チャンク.座標, チャンク.地表材質.材質データ.buffer)
        if (材質結果.種別 === '失敗') {
            throw new Error(`チャンク(${チャンク.座標.x},${チャンク.座標.z})材質重みの保存失敗: ${材質結果.エラー.種別} ${材質結果.エラー.説明}`)
        }
    }
}

function 区画割りの整合を確認する(保存済み: 世界の区画割り, 状態側: 世界の区画割り): void {
    if (
        保存済み.一辺のメートル !== 状態側.一辺のメートル ||
        保存済み.軸あたりチャンク数 !== 状態側.軸あたりチャンク数 ||
        保存済み.チャンクあたり格子解像度 !== 状態側.チャンクあたり格子解像度
    ) {
        throw new Error(`大域世界構造の区画割りとチャンク状態の区画割りが一致しない: 保管庫(${保存済み.一辺のメートル}m, ${保存済み.軸あたりチャンク数}軸, 解像度${保存済み.チャンクあたり格子解像度}) vs 状態(${状態側.一辺のメートル}m, ${状態側.軸あたりチャンク数}軸, 解像度${状態側.チャンクあたり格子解像度})`)
    }
}
