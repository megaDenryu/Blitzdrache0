import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import type { 編集コマンド } from '../生成/編集資源契約.ts'
import { 編集コマンド一括適用サービス } from '../ツール/チャンク編集/操作コマンド/index.ts'
import { 偽保管庫接続 } from './偽保管庫接続の下ごしらえ.ts'
import { コマンドJSON文字列を復元する } from './コマンドJSON解析.ts'

describe('ヘッドレス編集コマンド一括適用のテスト', () => {
    it('偽保管庫接続へ初期状態から14枝のコマンドを適用し、大域高さ格子を書かずにチャンクが保存されること', async () => {
        const 偽保管庫 = new 偽保管庫接続()
        const チャンク座標 = { x: 0, z: 0 }

        const コマンド一覧: 編集コマンド[] = [
            { 種類: '造成筆致', 値: { 種別: '盛る', 通過点列: [{ x: 0, y: 0, z: 0 }], 半径メートル: 15, 強さ: 3.5 } },
            { 種類: '材質の筆致', 値: { 層: '泥', 通過点列: [{ x: 0, y: 0, z: 0 }], 半径メートル: 10, 流量: 0.5 } },
            { 種類: '道路点を追加する', 値: { 対象: { 種類: 'チャンク', 値: { チャンク座標, 道路添字: 0 } }, 位置: { x: 20, y: 5, z: 20 } } },
            { 種類: '道路点を挿入する', 値: { 対象: { 種類: 'チャンク', 値: { チャンク座標, 道路添字: 0 } }, 添字: 1, 位置: { x: 0, y: 5, z: 0 } } },
            { 種類: '道路点を移動する', 値: { 対象: { 種類: 'チャンク', 値: { チャンク座標, 道路添字: 0 } }, 添字: 0, 新しい位置: { x: -60, y: 6, z: -60 } } },
            { 種類: '道路点を削除する', 値: { 対象: { 種類: 'チャンク', 値: { チャンク座標, 道路添字: 0 } }, 添字: 1 } },
            { 種類: '建物を配置する', 値: { チャンク座標, 建物: { 識別子: '家屋_H', 種別: '家屋', 位置: { x: 10, y: 2, z: 10 }, 向きラジアン: 0, 基礎半径メートル: 6, なじみ半径メートル: 12 } } },
            { 種類: '建物を移動する', 値: { チャンク座標, 識別子: '家屋_H', 新しい位置: { x: 15, y: 3, z: 15 }, 新しい向きラジアン: 1.0 } },
            { 種類: '建物を削除する', 値: { チャンク座標, 識別子: '家屋_H' } },
            { 種類: '散布設定を変更する', 値: { チャンク座標, 新しい設定: { 最小間隔メートル: 8.0, 乱数の種: 18446744073709551615n } } },
            { 種類: '道路に合わせて切土盛土する', 値: { チャンク座標 } },
            { 種類: '建物を配置する', 値: { チャンク座標, 建物: { 識別子: '塔_H', 種別: '塔', 位置: { x: -10, y: 8, z: -10 }, 向きラジアン: 0, 基礎半径メートル: 5, なじみ半径メートル: 10 } } },
            { 種類: '建物基礎を平坦化する', 値: { チャンク座標, 建物識別子: '塔_H' } },
            { 種類: '急勾配を岩肌へベイクする', 値: { チャンク座標 } },
            { 種類: '道路下を泥へベイクする', 値: { チャンク座標 } },
        ]

        const サービス = new 編集コマンド一括適用サービス(偽保管庫)
        const 適用件数 = await サービス.一括適用する(コマンド一覧)
        assert.strictEqual(適用件数, コマンド一覧.length, '全コマンド件数が返されること')

        assert.ok(偽保管庫.保存された大域構造 !== null, '初期時は大域世界構造が保存されること')
        assert.strictEqual(偽保管庫.保存された大域高さ格子, null, '大域高さ格子は一切保存されないこと')

        const 保存チャンク = 偽保管庫.保存されたチャンク構造マップ.get('0,0')
        assert.ok(保存チャンク !== undefined, 'チャンク(0,0)の構造が保存されること')
        assert.strictEqual(保存チャンク.散布.乱数の種, 18446744073709551615n, '散布の乱数の種が2^53超えで保存されること')
        assert.strictEqual(保存チャンク.建物一覧.length, 1, '建物が保存されること')
        assert.strictEqual(保存チャンク.建物一覧[0]?.識別子, '塔_H', '配置された建物が一致すること')

        const 保存高さ = 偽保管庫.保存されたチャンク高さマップ.get('0,0')
        assert.ok(保存高さ !== undefined, 'チャンク(0,0)の高さ格子が保存されること')

        const 保存材質 = 偽保管庫.保存されたチャンク材質マップ.get('0,0')
        assert.ok(保存材質 !== undefined, 'チャンク(0,0)の材質重みが保存されること')
    })

    it('保管庫に既存の大域構造がある場合、ヘッドレス保存で既存大域構造が上書きされないこと', async () => {
        const 偽保管庫 = new 偽保管庫接続()
        const 既存道路 = [{ x: 100, y: 0, z: 200 }]
        偽保管庫.保存された大域構造 = {
            区画割り: { 一辺のメートル: 1024, 軸あたりチャンク数: 4, チャンクあたり格子解像度: 128 },
            広域道路一覧: [{ 制御点列: 既存道路, 全幅メートル: 10, 細分割数: 50 }],
        }
        const チャンク座標 = { x: 0, z: 0 }
        const サービス = new 編集コマンド一括適用サービス(偽保管庫)
        await サービス.一括適用する([
            { 種類: '道路下を泥へベイクする', 値: { チャンク座標 } },
        ])
        assert.deepStrictEqual(偽保管庫.保存された大域構造.広域道路一覧[0]?.制御点列, 既存道路, '既存広域道路が上書きされないこと')
        assert.strictEqual(偽保管庫.保存された大域高さ格子, null, '大域高さ格子は保存されないこと')
    })

    it('等高線3本から高さ場を生成し粗マスで岩を塗って地形を生成するコマンド列のJSONがヘッドレス経路で適用できること', async () => {
        const 偽保管庫 = new 偽保管庫接続()
        const 座標 = { チャンク座標: { x: 0, z: 0 } }
        const 正方形 = (半辺: number, 高さ: number) => ({ 高さメートル: 高さ, 頂点列: [{ x: -半辺, z: -半辺 }, { x: 半辺, z: -半辺 }, { x: 半辺, z: 半辺 }, { x: -半辺, z: 半辺 }], 閉じている: true })
        const コマンドJSON = JSON.stringify([
            { 種類: '等高線を追加する', 値: { ...座標, 等高線: 正方形(100, 4) } },
            { 種類: '等高線を追加する', 値: { ...座標, 等高線: 正方形(60, 10) } },
            { 種類: '等高線を追加する', 値: { ...座標, 等高線: 正方形(20, 16) } },
            { 種類: '等高線から高さ場を生成する', 値: 座標 },
            { 種類: '粗マスを塗る', 値: { ...座標, 粗マスの一辺の升目数: 8, 塗り一覧: [{ 列: 8, 行: 8, 高さメートル: null, 層: '岩' }] } },
            { 種類: '粗マスから地形を生成する', 値: 座標 },
        ])
        const コマンド列 = コマンドJSON文字列を復元する(コマンドJSON)
        const 適用件数 = await new 編集コマンド一括適用サービス(偽保管庫).一括適用する(コマンド列)
        assert.strictEqual(適用件数, 6)

        const 保存チャンク = 偽保管庫.保存されたチャンク構造マップ.get('0,0')
        assert.ok(保存チャンク !== undefined, 'チャンク(0,0)の構造が保存されること')
        assert.strictEqual(保存チャンク.見下ろし図の下書き.等高線一覧.length, 3, '等高線3本が下書きとして保存されること')
        assert.deepStrictEqual(保存チャンク.見下ろし図の下書き.粗マスの塗り一覧, [{ 列: 8, 行: 8, 高さメートル: null, 層: '岩' }])
        const 保存高さ = 偽保管庫.保存されたチャンク高さマップ.get('0,0')
        assert.ok(保存高さ !== undefined)
        const 高さ = new Float32Array(保存高さ)
        const 解像度 = 129
        assert.ok(Math.abs((高さ[64 * 解像度 + 64] ?? 0) - 16) < 0.05, `中心は内側の等高線の高さ16で平坦になるべき: ${高さ[64 * 解像度 + 64]}`)
        const 保存材質 = 偽保管庫.保存されたチャンク材質マップ.get('0,0')
        assert.ok(保存材質 !== undefined)
        const 材質 = new Uint8Array(保存材質)
        assert.strictEqual(材質[((68 * 解像度) + 68) * 4 + 2], 255, '塗った粗マス(8,8)の中心は岩100%になるべき')
    })
})
