import type { プロジェクト保管庫接続 } from '../境界/通信/index.ts'
import type { チャンク座標 } from '../生成/編集資源契約.ts'
import { ワールド編集状態, 初期ワールド状態を生成する } from '../ツール/チャンク編集/編集モデル/index.ts'

// 保管庫から大域世界およびチャンク資源を読み出し、ワールド編集状態を復元する。
export async function ワールド状態を復元する(
    保管庫: プロジェクト保管庫接続,
    対象チャンク座標一覧: readonly チャンク座標[] = [{ x: 0, z: 0 }],
): Promise<ワールド編集状態> {
    const 大域構造結果 = await 保管庫.大域世界の構造を読む()
    if (大域構造結果.種別 === '失敗') {
        throw new Error(`大域世界構造の読込失敗: ${大域構造結果.エラー.種別} ${大域構造結果.エラー.説明}`)
    }
    if (大域構造結果.種別 === '無し') {
        const 初期状態 = 初期ワールド状態を生成する()
        初期状態.選択中チャンク座標 = 対象チャンク座標一覧[0] ?? { x: 0, z: 0 }
        return 初期状態
    }

    const 大域高さ結果 = await 保管庫.大域世界の高さ格子を読む()
    const 大域高さデータ = 大域高さ結果.種別 === '成功' ? new Float32Array(大域高さ結果.値) : undefined
    const 状態 = new ワールド編集状態(大域構造結果.値, 大域高さデータ)

    for (const 座標 of 対象チャンク座標一覧) {
        await チャンクを読み込んで登録する(保管庫, 状態, 座標)
    }
    状態.選択中チャンク座標 = 対象チャンク座標一覧[0] ?? { x: 0, z: 0 }
    return 状態
}

async function チャンクを読み込んで登録する(
    保管庫: プロジェクト保管庫接続,
    状態: ワールド編集状態,
    座標: チャンク座標,
): Promise<void> {
    const 構造結果 = await 保管庫.チャンクの構造を読む(座標)
    if (構造結果.種別 === '失敗') {
        throw new Error(`チャンク(${座標.x},${座標.z})構造の読込失敗: ${構造結果.エラー.種別} ${構造結果.エラー.説明}`)
    }
    if (構造結果.種別 === '成功') {
        const 高さ結果 = await 保管庫.チャンクの高さ格子を読む(座標)
        const 材質結果 = await 保管庫.チャンクの材質重みを読む(座標)
        const 高さデータ = 高さ結果.種別 === '成功' ? new Float32Array(高さ結果.値) : undefined
        const 材質データ = 材質結果.種別 === '成功' ? new Uint8Array(材質結果.値) : undefined
        状態.チャンクを登録する(座標, 構造結果.値, 高さデータ, 材質データ)
    } else {
        const 初期 = 初期ワールド状態を生成する(座標, 状態.大域世界構造)
        const 初期チャンク = 初期.チャンクを取得する(座標)
        状態.チャンクを登録する(
            座標,
            初期チャンク.構造を取得する(),
            初期チャンク.高さ場.格子データ,
            初期チャンク.地表材質.材質データ,
        )
    }
}
