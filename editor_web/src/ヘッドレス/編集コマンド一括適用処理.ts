import type { 編集コマンド, チャンク座標 } from '../生成/編集資源契約.ts'
import type { プロジェクト保管庫接続 } from '../境界/通信/index.ts'
import { 編集コマンドを適用する } from '../ツール/チャンク編集/操作コマンド/index.ts'
import { ワールド状態を復元する } from './ワールド復元.ts'
import { ワールド状態を保存する } from './ワールド保存.ts'

// 保管庫から資源を読み、契約13枝の同一TS適用実装でコマンド列を適用し、検証付きで保存する。
export async function 編集コマンドを一括適用する(
    保管庫: プロジェクト保管庫接続,
    コマンド列: readonly 編集コマンド[],
): Promise<number> {
    const 対象チャンク座標一覧 = コマンド列からチャンク座標一覧を抽出する(コマンド列)
    const 状態 = await ワールド状態を復元する(保管庫, 対象チャンク座標一覧)

    for (const コマンド of コマンド列) {
        チャンク座標を同期する(状態, コマンド)
        編集コマンドを適用する(状態, コマンド)
    }

    await ワールド状態を保存する(保管庫, 状態)
    return コマンド列.length
}

function チャンク座標を同期する(
    状態: { 選択中チャンク座標: チャンク座標 | null },
    コマンド: 編集コマンド,
): void {
    if ('チャンク座標' in コマンド.値) {
        状態.選択中チャンク座標 = コマンド.値.チャンク座標
    } else if ('対象' in コマンド.値 && コマンド.値.対象.種類 === 'チャンク') {
        状態.選択中チャンク座標 = コマンド.値.対象.値
    }
}

function コマンド列からチャンク座標一覧を抽出する(
    コマンド列: readonly 編集コマンド[],
): readonly チャンク座標[] {
    const マップ = new Map<string, チャンク座標>()
    マップ.set('0,0', { x: 0, z: 0 })
    for (const コマンド of コマンド列) {
        if ('チャンク座標' in コマンド.値) {
            const c = コマンド.値.チャンク座標
            マップ.set(`${c.x},${c.z}`, c)
        } else if ('対象' in コマンド.値 && コマンド.値.対象.種類 === 'チャンク') {
            const c = コマンド.値.対象.値
            マップ.set(`${c.x},${c.z}`, c)
        }
    }
    return Array.from(マップ.values())
}
