import { deepStrictEqual, strictEqual } from 'node:assert/strict'
import { describe, it } from 'node:test'
import { 視点のポインタ操作係 } from './視点のポインタ操作係.ts'
import type { カメラ操作対象ビュー } from './カメラ操作適用器.ts'

// 何が呼ばれたかだけを記録する偽のカメラ制御。three.jsを持ち込まずに割り当てを検査するために使う。
class 記録するカメラ制御 {
    public readonly 呼ばれた並び: string[] = []

    public 回転する(デルタX: number, デルタY: number): void {
        this.呼ばれた並び.push(`回転 ${デルタX} ${デルタY}`)
    }

    public 移動する(デルタX: number, デルタY: number): void {
        this.呼ばれた並び.push(`移動 ${デルタX} ${デルタY}`)
    }

    public 注視点を取得する(): { x: number; y: number; z: number } {
        return { x: 0, y: 0, z: 0 }
    }
}

// 中ボタンの押しは既定動作を止めるため、偽の事象もその口を持つ。
function ポインタ事象を作る(ボタン: number, 横: number, 縦: number): MouseEvent {
    return { button: ボタン, clientX: 横, clientY: 縦, preventDefault: () => {} } as unknown as MouseEvent
}

function 準備する(): { 制御: 記録するカメラ制御; 係: 視点のポインタ操作係 } {
    const 制御 = new 記録するカメラ制御()
    const ビュー: カメラ操作対象ビュー = { カメラ制御: 制御, 注視点表示制御: { 操作された: () => {} } }
    return { 制御, 係: new 視点のポインタ操作係(ビュー) }
}

describe('視点のポインタ操作係', () => {
    it('右ドラッグが視点の回転になる', () => {
        const { 制御, 係 } = 準備する()
        係.押された(ポインタ事象を作る(2, 100, 100))
        strictEqual(係.視点の操作として動かしたか(ポインタ事象を作る(2, 110, 130)), true)
        deepStrictEqual(制御.呼ばれた並び, ['回転 10 30'])
    })

    it('中ドラッグが視点の平行移動になる', () => {
        const { 制御, 係 } = 準備する()
        係.押された(ポインタ事象を作る(1, 100, 100))
        strictEqual(係.視点の操作として動かしたか(ポインタ事象を作る(1, 90, 100)), true)
        deepStrictEqual(制御.呼ばれた並び, ['移動 -10 0'])
    })

    it('左ドラッグは視点の操作にならず、編集の操作へ回る', () => {
        const { 制御, 係 } = 準備する()
        係.押された(ポインタ事象を作る(0, 100, 100))
        strictEqual(係.視点の操作として動かしたか(ポインタ事象を作る(0, 120, 100)), false)
        strictEqual(係.左ボタン押下中, true)
        deepStrictEqual(制御.呼ばれた並び, [])
    })

    it('どのボタンも押していない動きは視点の操作にならない', () => {
        const { 制御, 係 } = 準備する()
        strictEqual(係.視点の操作として動かしたか(ポインタ事象を作る(0, 120, 100)), false)
        deepStrictEqual(制御.呼ばれた並び, [])
    })

    // モードを持つ道具でも視点の操作は同じ手で効く。割り当てはモードを引数に取らないため、
    // 同じ係を使い回しても、間に編集の操作(左ドラッグ)が挟まっても、右ドラッグは回転のままである。
    it('編集の操作を挟んでも右ドラッグの割り当ては変わらない', () => {
        const { 制御, 係 } = 準備する()
        係.押された(ポインタ事象を作る(0, 100, 100))
        係.視点の操作として動かしたか(ポインタ事象を作る(0, 120, 100))
        係.離された(ポインタ事象を作る(0, 120, 100))
        係.押された(ポインタ事象を作る(2, 120, 100))
        strictEqual(係.視点の操作として動かしたか(ポインタ事象を作る(2, 125, 100)), true)
        deepStrictEqual(制御.呼ばれた並び, ['回転 5 0'])
    })

    it('右ボタンを押したままなら左ボタンを足しても回転のままである', () => {
        const { 制御, 係 } = 準備する()
        係.押された(ポインタ事象を作る(2, 100, 100))
        係.押された(ポインタ事象を作る(0, 100, 100))
        strictEqual(係.視点の操作として動かしたか(ポインタ事象を作る(0, 108, 100)), true)
        deepStrictEqual(制御.呼ばれた並び, ['回転 8 0'])
    })
})
