export type ポインタ操作種別 = 'カメラ回転' | 'カメラ平行移動' | '主作業'

// 三次元を持つエディター全体の既定の割り当て。右ドラッグ=視点の回転、中ドラッグ=視点の平行移動、
// 左ドラッグ=そのときの編集の操作(選択・配置・筆致)である。引数にモードを取らないのは、
// 視点の操作がモードによらず常に同じ手で効くことを型の側で守るためである。
// ホイールの寄り引きはこの関数の対象外であり、呼び出し元が常時処理する。
// 参照: `_doc/設計/ゲーム開発用エディター基盤.md`「判断13」
export function ポインタ操作の割り当てを決める(ボタン: number): ポインタ操作種別 {
    if (ボタン === 2) return 'カメラ回転'
    if (ボタン === 1) return 'カメラ平行移動'
    return '主作業'
}
