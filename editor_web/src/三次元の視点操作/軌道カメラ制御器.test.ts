import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 軌道カメラ制御器 } from './軌道カメラ制御器.ts'

// 透視カメラの位置反映だけを記録する偽物。実物はThree.jsのPerspectiveCameraを
// 内部に持つが、軌道カメラ制御器が使うのは「位置を設定する」「注視点を設定する」の
// 2メソッドだけであり、この偽物で回転計算の符号を検証できる。
class 位置記録カメラ {
    位置履歴: { x: number; y: number; z: number }[] = []

    位置を設定する(x: number, y: number, z: number): this {
        this.位置履歴.push({ x, y, z })
        return this
    }

    注視点を設定する(): this {
        return this
    }
}

describe('軌道カメラ制御器の昇降', () => {
    it('正のデルタ(E)で注視点の高さが上がり、カメラの高さも同じ分だけ上がること', () => {
        const カメラ = new 位置記録カメラ()
        const 制御器 = new 軌道カメラ制御器(カメラ, 100, 10, 1000)

        const 昇降前高さ = カメラ.位置履歴.at(-1)?.y
        assert.ok(昇降前高さ !== undefined)

        制御器.昇降する(10)

        const 昇降後高さ = カメラ.位置履歴.at(-1)?.y
        assert.ok(昇降後高さ !== undefined)
        assert.ok(昇降後高さ > 昇降前高さ, `E(正のデルタ)で高さは上がるべき(前:${昇降前高さ}, 後:${昇降後高さ})`)
    })

    it('負のデルタ(Q)で注視点の高さが下がること', () => {
        const カメラ = new 位置記録カメラ()
        const 制御器 = new 軌道カメラ制御器(カメラ, 100, 10, 1000)

        const 昇降前高さ = カメラ.位置履歴.at(-1)?.y
        assert.ok(昇降前高さ !== undefined)

        制御器.昇降する(-10)

        const 昇降後高さ = カメラ.位置履歴.at(-1)?.y
        assert.ok(昇降後高さ !== undefined)
        assert.ok(昇降後高さ < 昇降前高さ, `Q(負のデルタ)で高さは下がるべき(前:${昇降前高さ}, 後:${昇降後高さ})`)
    })
})

describe('軌道カメラ制御器の縦回転の符号', () => {
    it('下方向へドラッグする(デルタYが正)と、カメラの高さが上がり見下ろす方向へ回転すること', () => {
        const カメラ = new 位置記録カメラ()
        const 制御器 = new 軌道カメラ制御器(カメラ, 100, 10, 1000)

        const 回転前高さ = カメラ.位置履歴.at(-1)?.y
        assert.ok(回転前高さ !== undefined, '構築直後に初期位置が反映されているべき')

        制御器.回転する(0, 10)

        const 回転後高さ = カメラ.位置履歴.at(-1)?.y
        assert.ok(回転後高さ !== undefined, '回転する呼び出し後に位置が反映されているべき')
        assert.ok(
            回転後高さ > 回転前高さ,
            `下方向ドラッグでカメラの高さは上がるべき(前:${回転前高さ}, 後:${回転後高さ})`,
        )
    })

    it('上方向へドラッグする(デルタYが負)と、カメラの高さが下がり水平に近づく方向へ回転すること', () => {
        const カメラ = new 位置記録カメラ()
        const 制御器 = new 軌道カメラ制御器(カメラ, 100, 10, 1000)

        const 回転前高さ = カメラ.位置履歴.at(-1)?.y
        assert.ok(回転前高さ !== undefined)

        制御器.回転する(0, -10)

        const 回転後高さ = カメラ.位置履歴.at(-1)?.y
        assert.ok(回転後高さ !== undefined)
        assert.ok(
            回転後高さ < 回転前高さ,
            `上方向ドラッグでカメラの高さは下がるべき(前:${回転前高さ}, 後:${回転後高さ})`,
        )
    })
})
