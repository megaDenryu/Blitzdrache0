// 文書の表示名が変わったことを受ける2つの口。ツールごとの実装が満たす。
// 見えを合わせる先は文書タブの見出しであり、コマンドを積む先はそのツールの操作履歴である。
export interface I表示名の編集の届け先 {
    表示名の見えを合わせる(表示名: string): void
    表示名を変えるコマンドを積む(新しい表示名: string): void
}

// 文書の表示名の入力を、取り消し1回ぶんのコマンドへまとめる係。
//
// 1文字打つたびにコマンドを積むと、名前を10文字書き換えただけで取り消しの段が10増え、
// 取り消しが実質使えなくなる。打っている間はコマンドを積まず、見えだけを追随させ、
// 欄から離れた(または入力が確定した)ときに1つだけ積む。
// 打ち込みのドラッグ・つまみのドラッグと同じ規律であり、取り消しの単位を人の操作へ揃える。
// 参照: `_doc/設計/楽曲エディター.md`「判断13」
//
// 楽曲と建物のどちらのツールも同じ規律で動く必要があるため、規律の本体をここ1箇所に置く。
export class 表示名の編集をまとめる係 {
    private _正本の表示名: string
    private _最後に見えを合わせた表示名: string | null = null

    public constructor(初期の表示名: string, private readonly _届け先: I表示名の編集の届け先) {
        this._正本の表示名 = 初期の表示名
    }

    // 欄へ1文字打たれるたびに呼ぶ。正本は変えず、見えだけを追随させる。
    public 表示名が入力された(入力中の表示名: string): void {
        this.見えを合わせる(入力中の表示名)
    }

    // 欄から離れたとき、または入力が確定したときに呼ぶ。ここで初めてコマンドを1つ積む。
    // 打つ前と同じ名前へ戻っていたときに積まないのは、何も変わらない取り消しの段を作らないためである。
    public 表示名の入力が決まった(新しい表示名: string): void {
        if (新しい表示名 === this._正本の表示名) return
        this._届け先.表示名を変えるコマンドを積む(新しい表示名)
    }

    // 正本の側で表示名が変わったときに呼ぶ(コマンドの適用後・取り消し・やり直し・保存物の読み直し)。
    public 正本の表示名に合わせる(表示名: string): void {
        this._正本の表示名 = 表示名
        this.見えを合わせる(表示名)
    }

    private 見えを合わせる(表示名: string): void {
        if (表示名 === this._最後に見えを合わせた表示名) return
        this._最後に見えを合わせた表示名 = 表示名
        this._届け先.表示名の見えを合わせる(表示名)
    }
}
