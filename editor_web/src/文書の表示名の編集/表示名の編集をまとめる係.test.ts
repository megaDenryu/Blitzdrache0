import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { 表示名の編集をまとめる係, type I表示名の編集の届け先 } from './表示名の編集をまとめる係.ts'

class 記録する届け先 implements I表示名の編集の届け先 {
    public 見えを合わせた表示名: string[] = []
    public 積んだコマンドの表示名: string[] = []

    public 表示名の見えを合わせる(表示名: string): void {
        this.見えを合わせた表示名.push(表示名)
    }

    public 表示名を変えるコマンドを積む(新しい表示名: string): void {
        this.積んだコマンドの表示名.push(新しい表示名)
    }
}

describe('表示名の編集をまとめる係', () => {
    it('打っている間はコマンドを1つも積まず、見えだけを追随させる', () => {
        const 届け先 = new 記録する届け先()
        const 係 = new 表示名の編集をまとめる係('もとの名前', 届け先)

        for (const 途中の綴り of ['あ', 'あか', 'あかい', 'あかいや', 'あかいやね']) {
            係.表示名が入力された(途中の綴り)
        }

        assert.deepStrictEqual(届け先.積んだコマンドの表示名, [])
        assert.deepStrictEqual(届け先.見えを合わせた表示名, ['あ', 'あか', 'あかい', 'あかいや', 'あかいやね'])
    })

    it('入力が決まったときに、5文字打っていてもコマンドは1つだけ積まれる', () => {
        const 届け先 = new 記録する届け先()
        const 係 = new 表示名の編集をまとめる係('もとの名前', 届け先)

        for (const 途中の綴り of ['あ', 'あか', 'あかい', 'あかいや', 'あかいやね']) {
            係.表示名が入力された(途中の綴り)
        }
        係.表示名の入力が決まった('あかいやね')

        assert.deepStrictEqual(届け先.積んだコマンドの表示名, ['あかいやね'])
    })

    it('打つ前と同じ名前へ戻して決まったときは、コマンドを積まない', () => {
        const 届け先 = new 記録する届け先()
        const 係 = new 表示名の編集をまとめる係('もとの名前', 届け先)

        係.表示名が入力された('もとの名')
        係.表示名が入力された('もとの名前')
        係.表示名の入力が決まった('もとの名前')

        assert.deepStrictEqual(届け先.積んだコマンドの表示名, [])
    })

    it('正本が変わったら次の確定の判定の基準もその名前になる', () => {
        const 届け先 = new 記録する届け先()
        const 係 = new 表示名の編集をまとめる係('もとの名前', 届け先)

        係.正本の表示名に合わせる('保存されていた名前')
        係.表示名の入力が決まった('保存されていた名前')
        assert.deepStrictEqual(届け先.積んだコマンドの表示名, [])

        係.表示名の入力が決まった('あたらしい名前')
        assert.deepStrictEqual(届け先.積んだコマンドの表示名, ['あたらしい名前'])
    })

    it('同じ表示名を続けて渡されても、見えを合わせる知らせは1回だけになる', () => {
        const 届け先 = new 記録する届け先()
        const 係 = new 表示名の編集をまとめる係('もとの名前', 届け先)

        係.表示名が入力された('あたらしい名前')
        係.正本の表示名に合わせる('あたらしい名前')
        係.正本の表示名に合わせる('あたらしい名前')

        assert.deepStrictEqual(届け先.見えを合わせた表示名, ['あたらしい名前'])
    })

    it('保存物を読み直して正本が変わったら、見えを合わせる知らせが届く', () => {
        const 届け先 = new 記録する届け先()
        const 係 = new 表示名の編集をまとめる係('あたらしい建物', 届け先)

        係.正本の表示名に合わせる('保存されていた名前')

        assert.deepStrictEqual(届け先.見えを合わせた表示名, ['保存されていた名前'])
        assert.deepStrictEqual(届け先.積んだコマンドの表示名, [])
    })
})
