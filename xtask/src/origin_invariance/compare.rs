//! 読み戻し画像2枚のバイト比較と結果表示。
//! 担当する工程: 画像の対と求める向き(一致か不一致か)を受け取り、合否と差分の内訳を持つ判定結果を返す。

use std::process::ExitCode;

use super::run::読み戻し画像;

/// 2枚がどう違うか。寸法やバイト長が違う場合は画素の差分を数えられないため、判別共用体で分ける。
enum 比較 {
    形が違う(String),
    差分あり { 件数: usize, 先頭: usize },
    完全一致,
}

/// 合格の説明と不合格の理由はどちらも表示するが、終了コードへの寄与が逆になるため判別共用体で持つ。
enum 合否 {
    合格(String),
    不合格(String),
}

pub(super) struct 判定結果 {
    名前: &'static str,
    合否: 合否,
}

fn 比較する(左: &読み戻し画像, 右: &読み戻し画像) -> 比較 {
    if 左.寸法宣言 != 右.寸法宣言 {
        return 比較::形が違う(format!("寸法が違う: {} と {}", 左.寸法宣言.trim(), 右.寸法宣言.trim()));
    }
    if 左.画素バイト列.len() != 右.画素バイト列.len() {
        return 比較::形が違う(format!("バイト長が違う: {} と {}", 左.画素バイト列.len(), 右.画素バイト列.len()));
    }
    let 差分一覧: Vec<usize> = 左
        .画素バイト列
        .iter()
        .zip(右.画素バイト列.iter())
        .enumerate()
        .filter_map(|(添字, (左値, 右値))| (左値 != 右値).then_some(添字))
        .collect();
    match 差分一覧.first() {
        None => 比較::完全一致,
        Some(先頭) => 比較::差分あり {
            件数: 差分一覧.len(),
            先頭: *先頭,
        },
    }
}

/// バイト一致を求める判定。原点移動不変性そのものを測る。
pub(super) fn 一致を求める(名前: &'static str, 左: &読み戻し画像, 右: &読み戻し画像) -> 判定結果 {
    let 合否 = match 比較する(左, 右) {
        比較::完全一致 => 合否::合格("バイト一致".to_string()),
        比較::形が違う(理由) => 合否::不合格(理由),
        比較::差分あり { 件数, 先頭 } => 合否::不合格(format!("差分バイト数{件数}件、最初の差分はバイト{先頭}")),
    };
    判定結果 { 名前, 合否 }
}

/// バイト不一致を求める判定(負の対照)。一致したら、指定した条件が描画へ届いていないか、大座標で微小移動が丸めに消えている。
pub(super) fn 不一致を求める(名前: &'static str, 左: &読み戻し画像, 右: &読み戻し画像) -> 判定結果 {
    let 合否 = match 比較する(左, 右) {
        比較::差分あり { 件数, 先頭 } => 合否::合格(format!("差分バイト数{件数}件、最初の差分はバイト{先頭}")),
        比較::完全一致 => 合否::不合格("差分が0件であり、条件の違いが描画へ届いていない".to_string()),
        比較::形が違う(理由) => 合否::不合格(format!("画素以外が違うため負の対照にならない: {理由}")),
    };
    判定結果 { 名前, 合否 }
}

pub(super) fn 結果を表示する(判定一覧: &[判定結果]) -> ExitCode {
    let mut 全て合格 = true;
    for 判定 in 判定一覧 {
        match &判定.合否 {
            合否::合格(説明) => println!("[xtask] 合格: {} — {説明}", 判定.名前),
            合否::不合格(理由) => {
                eprintln!("[xtask] 不合格: {} — {理由}", 判定.名前);
                全て合格 = false;
            }
        }
    }
    if 全て合格 {
        println!("[xtask] origin-invariance成功: 原点移動で画像が一致し、カメラの微小移動で画像が変わった");
        ExitCode::SUCCESS
    } else {
        ExitCode::FAILURE
    }
}
