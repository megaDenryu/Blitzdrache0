//! 通った実行が返す1文の組み立て。受け取るのは各判定の実測と絵の置き場、返すのは人が読む要約である。
//!
//! 段差の実測へ境界番号を添えるのは、実在しない境界を判定から外した実行では実測の並びが0番から連続しないためである。
//! 番号を添えないと、境界2の段差が境界0の段差として読まれる。
//!
//! 外した境界の綴りをここが必ず連結するのは、間引きを黙らせないためである。要約の組み立てが1箇所にあれば、
//! 「外したことを書き忘れた要約」を作れる場所も1箇所しかない。

use std::path::Path;

use super::composition::継ぎ目を見る構図;
use super::judgment::{境界の実在, 境界の段差, 対象から外した境界の綴り};

pub(super) struct 検収の実測<'実測> {
    pub(super) 分け方: &'実測 str,
    pub(super) 四区分の成立: [usize; 4],
    pub(super) 境界の実在: &'実測 [境界の実在],
    pub(super) 境界の影: Vec<(usize, usize)>,
    pub(super) 段差: Vec<境界の段差>,
    pub(super) 本番png: &'実測 Path,
    pub(super) 可視化png: &'実測 Path,
}

pub(super) fn 検収の要約を組み立てる(構図: 継ぎ目を見る構図, 実測: &検収の実測<'_>) -> String {
    let 成立の呼び名 = if 構図.影の画素で四区分の成立を見るか() {
        "影画素数"
    } else {
        "受光画素数"
    };
    format!(
        "構図は{}、{}、距離区分別の{成立の呼び名}{:?}、実在する境界の両側の影画素数{:?}、{}、{}、絵は{}と{}",
        構図.呼び名(),
        実測.分け方,
        実測.四区分の成立,
        実測.境界の影,
        段差の記述(実測),
        対象から外した境界の綴り(実測.境界の実在),
        実測.本番png.display(),
        実測.可視化png.display()
    )
}

fn 段差の記述(実測: &検収の実測<'_>) -> String {
    let 記述: Vec<String> = 実測
        .段差
        .iter()
        .map(|測定| {
            format!(
                "境界{}は段差{:.3}(距離区分の内側の勾配{:.3}、{})",
                測定.境界番号, 測定.段差, 測定.内側の勾配, 測定.内訳
            )
        })
        .collect();
    if 記述.is_empty() {
        return "輝度段差を測れた境界は無い".to_string();
    }
    記述.join("・")
}
