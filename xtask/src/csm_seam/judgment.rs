//! 継ぎ目の3つの判定。受け取るのは距離区分の地図と本番の絵、返すのは合否と実測値である。
//!
//! 距離区分の領域と影の内外は距離区分の可視化から読み、輝度の段差は本番のPCFの経路が出した絵から測る
//! (設計正本「検証の設計」層4: 最終判定は本番の画素に置く)。

mod existing_boundary;
mod step_breakdown;
mod verdict_names;

use super::band_map::距離区分の地図;
use super::boundary;
use super::run::輝度を求める;
use super::{影画素数の下限, 段差の絶対上限, 近傍の幅};
use crate::acceptance::{判定の破れ, 読み戻し画像};
pub(in crate::csm_seam) use existing_boundary::{
    境界ごとに数える, 境界の実在, 対象から外した境界の綴り, 継ぎ目を見られる境界があることを検査する
};
use verdict_names::{
    境界の近傍の判定名, 平均輝度を測る画素, 距離区分の受光画素の判定名, 距離区分の影の画素の判定名
};

pub(super) fn 全距離区分に影があることを検査する(地図: &距離区分の地図) -> Result<[usize; 4], 判定の破れ> {
    let 数 = 地図.距離区分別の影画素数();
    for (距離区分, &画素数) in 数.iter().enumerate() {
        if 画素数 == 0 {
            return Err(距離区分の影の画素の判定名(距離区分, 数).あるはずのものが無い破れ());
        }
    }
    Ok(数)
}

/// どの距離区分にも影の判定を受けた画素があることを見る。大規模世界の再配分では第4区分が遠景層を担当し、
/// 粗い遠景メッシュに自己遮蔽の影がほとんど出ないため、影の画素でなく受光画素の有無で4区分の成立を見る。
/// 参照: `_doc/設計/大規模世界の生成と遠景.md`第5段階の検査点5「4区分すべてに受光画素があり」
pub(super) fn 全距離区分に受光画素があることを検査する(地図: &距離区分の地図) -> Result<[usize; 4], 判定の破れ> {
    let 数 = 地図.距離区分別の受光画素数();
    for (距離区分, &画素数) in 数.iter().enumerate() {
        if 画素数 == 0 {
            return Err(距離区分の受光画素の判定名(距離区分, 数).あるはずのものが無い破れ());
        }
    }
    Ok(数)
}

/// 影が両側に実在する境界について、その数が下限に届くことを見る。片側で影がまばらになっていれば、
/// その側の距離区分が影を描けていない。影が片側に1画素も無い境界は、影を落とす物がその距離に無い構図であり、
/// 退行と区別できないため対象から外す(外したことは要約が名指す)。
pub(super) fn 実在する境界の両側の影が下限に届くことを検査する(
    一覧: &[境界の実在],
) -> Result<Vec<(usize, usize)>, 判定の破れ> {
    let mut 実測 = Vec::new();
    for 実在 in 一覧.iter().filter(|実在| 実在.影が両側にあるか()) {
        境界の近傍の判定名(実在.境界番号, "手前側の影の画素数").下限を課す(実在.手前側の影画素数, 影画素数の下限)?;
        境界の近傍の判定名(実在.境界番号, "奥側の影の画素数").下限を課す(実在.奥側の影画素数, 影画素数の下限)?;
        実測.push((実在.手前側の影画素数, 実在.奥側の影画素数));
    }
    Ok(実測)
}

/// 境界を挟む2つの距離区分の平均輝度の差を、同じ幅ぶん内側へ入った位置との差(距離区分の内側の勾配)と比べる。
/// 境界の段差が距離区分の内側の勾配を超えなければ、その段差は普通の陰影の変化に埋もれている。
pub(super) fn 実在する境界の輝度段差を検査する(
    地図: &距離区分の地図,
    本番: &読み戻し画像,
    一覧: &[境界の実在],
) -> Result<Vec<(f64, f64)>, 判定の破れ> {
    let mut 実測 = Vec::new();
    for 境界番号 in 一覧.iter().filter(|実在| 実在.影が両側にあるか()).map(|実在| 実在.境界番号) {
        let 近傍 = boundary::集める(地図, 境界番号, 1, 近傍の幅);
        let 内側 = boundary::集める(地図, 境界番号, 近傍の幅 + 1, 近傍の幅 * 2);
        let 近傍手前 = 平均輝度(本番, &近傍.手前側)?;
        let 近傍奥 = 平均輝度(本番, &近傍.奥側)?;
        let 段差 = (近傍手前 - 近傍奥).abs();
        let 勾配 = (近傍手前 - 平均輝度(本番, &内側.手前側)?)
            .abs()
            .max((近傍奥 - 平均輝度(本番, &内側.奥側)?).abs());
        let 内訳 = step_breakdown::内訳を述べる(地図, 本番, &近傍.手前側, &近傍.奥側);
        境界の近傍の判定名(境界番号, &format!("輝度段差({内訳}。距離区分の内側の勾配との比べ)")).上限を課す(段差, 勾配)?;
        境界の近傍の判定名(境界番号, &format!("輝度段差({内訳}。絶対上限との比べ)")).上限を課す(段差, 段差の絶対上限)?;
        実測.push((段差, 勾配));
    }
    Ok(実測)
}

fn 平均輝度(本番: &読み戻し画像, 添字一覧: &[usize]) -> Result<f64, 判定の破れ> {
    if 添字一覧.is_empty() {
        return Err(平均輝度を測る画素.あるはずのものが無い破れ());
    }
    let 数 = f64::from(u32::try_from(添字一覧.len()).unwrap_or(u32::MAX));
    Ok(添字一覧.iter().map(|&添字| 輝度を求める(本番, 添字)).sum::<f64>() / 数)
}
