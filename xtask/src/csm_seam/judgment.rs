//! 継ぎ目の3つの判定。受け取るのは帯地図と本番の絵、返すのは合否と実測値である。
//!
//! 帯の領域と影の内外は帯の可視化から読み、輝度の段差は本番のPCFの経路が出した絵から測る
//! (設計正本「検証の設計」層4: 最終判定は本番の画素に置く)。

use super::band_map::帯地図;
use super::boundary;
use super::run::実行結果;
use super::{境界の数, 帯の幅, 影画素数の下限, 段差の絶対上限};

pub(super) fn 全帯に影があることを検査する(地図: &帯地図) -> Result<[usize; 4], String> {
    let 数 = 地図.帯別の影画素数();
    for (帯, &画素数) in 数.iter().enumerate() {
        if 画素数 == 0 {
            return Err(format!("帯{帯}に影の画素が1つも無い: 帯別の影画素数は{数:?}である"));
        }
    }
    Ok(数)
}

/// 境界を挟む両側それぞれに影の画素があることを見る。片側で影が消えていれば、その側の帯が影を描けていない。
pub(super) fn 境界の両側に影があることを検査する(地図: &帯地図) -> Result<Vec<(usize, usize)>, String> {
    let mut 実測 = Vec::with_capacity(境界の数);
    for 境界番号 in 0..境界の数 {
        let 近傍 = boundary::集める(地図, 境界番号, 1, 帯の幅);
        let 手前 = 影の数(地図, &近傍.手前側);
        let 奥 = 影の数(地図, &近傍.奥側);
        if 手前 < 影画素数の下限 || 奥 < 影画素数の下限 {
            return Err(format!(
                "境界{境界番号}と{}の近傍で影の画素が足りない: 手前{手前}・奥{奥}(下限{影画素数の下限})",
                境界番号 + 1
            ));
        }
        実測.push((手前, 奥));
    }
    Ok(実測)
}

/// 境界を挟む2つの帯の平均輝度の差を、同じ幅ぶん内側へ入った位置との差(帯の内側の勾配)と比べる。
/// 境界の段差が帯の内側の勾配を超えなければ、その段差は普通の陰影の変化に埋もれている。
pub(super) fn 境界の輝度段差を検査する(地図: &帯地図, 本番: &実行結果) -> Result<Vec<(f64, f64)>, String> {
    let mut 実測 = Vec::with_capacity(境界の数);
    for 境界番号 in 0..境界の数 {
        let 近傍 = boundary::集める(地図, 境界番号, 1, 帯の幅);
        let 内側 = boundary::集める(地図, 境界番号, 帯の幅 + 1, 帯の幅 * 2);
        let 近傍手前 = 平均輝度(本番, &近傍.手前側)?;
        let 近傍奥 = 平均輝度(本番, &近傍.奥側)?;
        let 段差 = (近傍手前 - 近傍奥).abs();
        let 勾配 = (近傍手前 - 平均輝度(本番, &内側.手前側)?)
            .abs()
            .max((近傍奥 - 平均輝度(本番, &内側.奥側)?).abs());
        if 段差 > 勾配 || 段差 > 段差の絶対上限 {
            return Err(format!(
                "境界{境界番号}と{}の輝度段差{段差:.2}が許容を超えた(帯の内側の勾配{勾配:.2}、絶対上限{段差の絶対上限})",
                境界番号 + 1
            ));
        }
        実測.push((段差, 勾配));
    }
    Ok(実測)
}

fn 影の数(地図: &帯地図, 添字一覧: &[usize]) -> usize {
    添字一覧
        .iter()
        .filter(|&&添字| 地図.画素(添字 % 地図.幅, 添字 / 地図.幅).is_some_and(|画素| 画素.影の中))
        .count()
}

fn 平均輝度(本番: &実行結果, 添字一覧: &[usize]) -> Result<f64, String> {
    if 添字一覧.is_empty() {
        return Err("平均輝度を測る画素が1つも無い: 境界が画面に現れていない".to_string());
    }
    let 数 = u32::try_from(添字一覧.len()).map_err(|_| "画素数がu32に収まらない".to_string())?;
    Ok(添字一覧.iter().map(|&添字| 本番.輝度(添字)).sum::<f64>() / f64::from(数))
}
