//! 撮った絵の隣へ、どの構図で撮ったのかを書き残す工程。受け取るのは構図と実際に開いた世界の材料と分け方の行、
//! 返すのは書き込みの成否である。
//!
//! 置き場を分けただけでは取り違えを防げない。2つの構図の成果物は同じ`scene.png`という名前で別のディレクトリへ
//! 出るため、絵だけを開くとどちらの実行が書いたものか分からない。実際に、大規模世界の実行が失敗して絵を書かなかった
//! 回に、隣の置き場に残っていた検証用地形世界の絵を大規模世界のものと読み違えて「構図が配線されていない」という
//! 誤った診断が出た。絵の隣に世界の名前とアセットルートが平文で在れば、開いた瞬間に分かる。
//!
//! 分け方の行もここへ写す。判定はこの行をアプリの報告から直に読んで課しており、由来は後から人が読むための控えである。

use std::path::Path;

use super::composition::継ぎ目を見る構図;
use super::error::距離区分の継ぎ目の検収エラー;

const 由来のファイル名: &str = "由来.txt";

pub(super) fn 書く(
    置き場: &Path,
    構図: 継ぎ目を見る構図,
    アセットルート: &Path,
    分け方の行: &str,
) -> Result<(), 距離区分の継ぎ目の検収エラー> {
    let パス = 置き場.join(由来のファイル名);
    let 行一覧 = [
        format!("csm-seam-contract=v1 構図={}", 構図.呼び名()),
        format!("アセットルート={}", アセットルート.display()),
        format!("シーン={} 一日内秒={}", 構図.シーン名の綴り(), 構図.一日内秒()),
        format!(
            "要る分け方={}",
            if 構図.明示の境界を要るか() {
                "明示境界"
            } else {
                "実用分割"
            }
        ),
        format!("アプリが報告した分け方={分け方の行}"),
    ];
    std::fs::write(&パス, 行一覧.join("\n"))
        .map_err(|誤り| 距離区分の継ぎ目の検収エラー::由来を書けなかった {
            パス: パス.clone(), 誤り
        })
}
