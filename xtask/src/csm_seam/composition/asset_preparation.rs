//! 検収を走らせる前に、その構図が読む世界の素材を焼く局面。受け取るものは構図だけ、返すのは焼けたかどうかである。
//!
//! いつ呼ばれるか: 1回の検収につき1度、アプリを起こすより前である。構図の性質を答えるだけの他のメソッドと違い、
//! ここはディスクへ書く副作用を持つため分けて置く。
//!
//! 大規模世界が何もしないのは、8km×10kmの世界を`cargo xtask large-world-assets`が別に焼いており、
//! 継ぎ目の検収がそれを読むだけだからである。ここで焼き直すと1回の検収に数分の生成が乗る。

use super::継ぎ目を見る構図;
use crate::csm_seam::error::距離区分の継ぎ目の検収エラー;

impl 継ぎ目を見る構図 {
    pub(in crate::csm_seam) fn 要るアセットを用意する(self) -> Result<(), 距離区分の継ぎ目の検収エラー> {
        if self == Self::大規模世界 {
            return Ok(());
        }
        if crate::gen_source_assets::生成する() && crate::compile_assets::地形世界を既定で生成する() {
            return Ok(());
        }
        Err(距離区分の継ぎ目の検収エラー::検証用アセットを生成できなかった)
    }
}
