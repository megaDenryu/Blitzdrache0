//! その構図が継ぎ目の判定へ課す強さ。受け取るのは構図だけ、返すのはどの判定をどの形で課すかである。
//!
//! 世界ごとに強さが分かれるのは、影が届く範囲と受光面の起伏が構図で違うためである。箱の植生が全距離区分へ影を
//! 落とす検証用地形世界では、どの境界にも影があり内側の勾配も大きい。大規模世界は散布物が影を落とすようになった
//! あとも、影が届かない距離帯が両端に残る。最も近い距離区分では低い太陽が影を境界の帯の外へずらし、最も遠い
//! 距離区分には散布物が1体も存在しない。同じ強さを両方へ当てると、片方では退行を見逃し、もう片方では
//! 見えない差で落ちる。

use super::継ぎ目を見る構図;

impl 継ぎ目を見る構図 {
    /// 影が片側に1画素も無い境界を判定の対象から外すか。偽なら3つの境界すべてへ下限を課す。
    ///
    /// 間引きは大規模世界の構図だけのものである。検証用地形世界は箱の植生が全距離区分へ影を落とす構図であり、
    /// どの境界の手前側にも影がある。そこで影が消えたなら、それは構図の性質でなく退行である。間引きを効かせると
    /// その退行を「もともと影が無い」として見逃す。
    pub(in crate::csm_seam) fn 影の無い境界を判定から外すか(self) -> bool {
        match self {
            Self::検証用地形世界 => false,
            Self::大規模世界 => true,
        }
    }

    /// この構図が要る影の距離区分の分け方。大規模世界だけが名指しの境界で走る。
    pub(in crate::csm_seam) fn 明示の境界を要るか(self) -> bool {
        match self {
            Self::検証用地形世界 => false,
            Self::大規模世界 => true,
        }
    }

    /// 輝度段差を距離区分の内側の勾配とも比べるか。真なら勾配比と絶対上限の両方を、偽なら絶対上限だけを課す。
    ///
    /// 勾配比の判定は「段差が地形の起伏に紛れるか」を測るものであり、箱の植生が大きな明暗を作る検証用地形世界に
    /// 合わせた形である。大規模世界の受光面は平坦で内側の勾配が0へ近づくため、比が発散して視認できない段差でも
    /// 落ちる構造的な偏りを持つ。実測では受光どうしの段差2.997階調に対し内側の勾配0.534であり比では落ちるが、
    /// 絶対上限12階調の4分の1であり親の目視でも識別できなかった(2026-08-16の裁定)。
    /// 段差の出どころ(区分1と区分2でシャドウマップ1テクセルが覆う長さが約12倍違い、低い太陽で受光面の
    /// 自己遮蔽量が変わる)は将来の改善材料として外部台帳へ起票済みであり、内訳は落ちても通っても記録する。
    pub(in crate::csm_seam) fn 内側の勾配と比べるか(self) -> bool {
        match self {
            Self::検証用地形世界 => true,
            Self::大規模世界 => false,
        }
    }

    /// 距離区分の成立を影の画素で見るか、受光画素で見るか。
    pub(in crate::csm_seam) fn 影の画素で四区分の成立を見るか(self) -> bool {
        match self {
            Self::検証用地形世界 => true,
            Self::大規模世界 => false,
        }
    }
}
