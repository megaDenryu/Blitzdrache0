//! 大規模世界の固定構図で世界を開く起動の指定。受け取るものは無く、返すのはアプリへ渡す起動指定である。
//!
//! 視点と先読み半径は遠景の検収(`cargo xtask distant-view`)と同じにする。2つの検査点が同じ絵を別の観点から
//! 見る形にするためである。
//!
//! **時刻だけは遠景の検収と変える。** 正午で撮った実測では影の画素が4距離区分とも0件だった。この世界には
//! まだ立体物が無く、地形の自己遮蔽だけが影の出どころであるため、太陽が真上にあると受光面のどこにも影が
//! 落ちない。影が1画素も無い絵では継ぎ目の段差を測る対象が存在せず、検収は何も見ないまま通る。
//! 検証用地形世界と同じ夕方の時刻を採り、低い太陽が起伏の陰を受光面へ長く伸ばす条件で撮る。
//! 遠景の検査点は幾何と色の突き合わせであり時刻に依らないため、2つの検査点で時刻が違っても比較は成立する。
//!
//! 背景と後処理と時間再構成を外すのは検証用地形世界と同じ理由である。背景をクリア色のまま残して幾何と背景を
//! 色で分け、光のにじみが境界の段差を混ぜることを避け、フレームをまたぐ混合を入れない。
//!
//! 注意: 値は`xtask/src/distant_view/plan.rs`が表示する固定構図の契約と同じでなければならない。

use super::背景と光を外す選択肢;
use crate::acceptance::{アプリの起動指定, 描画フレーム数};

const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(360);
const 先読み半径: &str = "8";
const 容量上限バイト: &str = "536870912";
const カメラ方位度: &str = "180";
const カメラ俯角度: &str = "-11.0107";
/// 夕方の時刻。検証用地形世界の継ぎ目の検収と同じ値であり、低い太陽が起伏の陰を受光面へ長く伸ばす。
const 一日内秒: &str = "61200";

pub(super) fn 大規模世界で世界を開く指定を作る() -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(crate::fox_tour_launch::シーン名, フレーム数)
        .選択肢を足す("--streaming")
        .値を持つ選択肢を足す("--streaming-preload-radius", 先読み半径)
        .値を持つ選択肢を足す("--streaming-ram-limit", 容量上限バイト)
        .値を持つ選択肢を足す("--streaming-vram-limit", 容量上限バイト)
        .値を持つ選択肢を足す("--streaming-loader-workers", "1")
        .値を持つ選択肢を足す("--game", "fox_tour")
        .値を持つ選択肢を足す("--camera-yaw", カメラ方位度)
        .値を持つ選択肢を足す("--camera-pitch", カメラ俯角度)
        .値を持つ選択肢を足す("--time-of-day", 一日内秒)
        .値を持つ選択肢を足す("--depth-prepass", "equal")
        .選択肢をまとめて足す(&背景と光を外す選択肢)
}
