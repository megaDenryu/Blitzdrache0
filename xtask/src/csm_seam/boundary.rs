//! 距離区分の境界の近傍で、両側の距離区分の画素を集める工程。受け取るのは距離区分の地図と境界の番号と近傍の幅、返すのは両側の画素添字である。
//!
//! 列ごとに上から走査して、隣り合う2画素の距離区分が境界の2つの距離区分になる最初の位置を境界とする。この構図では
//! 距離区分は画面の縦方向に積み重なるため、列ごとの走査で境界の位置が1つに決まる。
//! 集めるのは境界からの距離が指定の幅までの画素だけであり、そこから離れた画素は距離区分の内側の対照として別に集める。

use super::band_map::距離区分の地図;

pub(super) struct 境界の近傍 {
    /// 手前側の距離区分(番号の小さい側)の画素添字。
    pub(super) 手前側: Vec<usize>,
    /// 奥側の距離区分(番号の大きい側)の画素添字。
    pub(super) 奥側: Vec<usize>,
}

/// `距離下限`から`距離上限`までの距離区分の画素を集める。1から始めれば境界に接する距離区分、幅の次から始めれば内側の対照になる。
pub(super) fn 集める(地図: &距離区分の地図, 境界番号: usize, 距離下限: usize, 距離上限: usize) -> 境界の近傍 {
    let mut 手前側 = Vec::new();
    let mut 奥側 = Vec::new();
    for x in 0..地図.幅 {
        let Some(境界y) = 境界の位置(地図, 境界番号, x) else {
            continue;
        };
        for 距離 in 距離下限..=距離上限 {
            for y in [境界y.checked_sub(距離), 境界y.checked_add(距離 - 1)].into_iter().flatten() {
                if y >= 地図.高さ {
                    continue;
                }
                let Some(画素) = 地図.画素(x, y) else {
                    continue;
                };
                if 画素.距離区分 == 境界番号 {
                    手前側.push(地図.添字(x, y));
                } else if 画素.距離区分 == 境界番号 + 1 {
                    奥側.push(地図.添字(x, y));
                }
            }
        }
    }
    境界の近傍 { 手前側, 奥側 }
}

/// 列`x`で、上下に隣り合う2画素の距離区分が`境界番号`と`境界番号 + 1`になる最初の位置(下側の行)を返す。
fn 境界の位置(地図: &距離区分の地図, 境界番号: usize, x: usize) -> Option<usize> {
    (1..地図.高さ).find(|&y| {
        let (Some(上), Some(下)) = (地図.画素(x, y - 1), 地図.画素(x, y)) else {
            return false;
        };
        let 組 = [上.距離区分, 下.距離区分];
        組.contains(&境界番号) && 組.contains(&(境界番号 + 1)) && 上.距離区分 != 下.距離区分
    })
}
