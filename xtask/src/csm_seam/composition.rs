//! どの世界のどの構図で継ぎ目を見るかの2通りと、構図ごとに変わる起動の材料。
//! 受け取るのは引数の綴り、返すのは構図と、その構図が要る世界・アセットルート・視点・判定の強さである。
//!
//! 2つを判別共用体で表すのは、世界とカメラと判定の組が構図ごとに固定で、混ぜると意味を成さないためである。
//! 検証用地形世界は5×5チャンクの受光面へ植生の群が影を落とす構図であり、4距離区分すべてに影の画素が出る。
//! 大規模世界は8km×10kmの固定構図であり、第4区分が担当する遠景層は粗い面で自己遮蔽の影がほとんど出ないため、
//! 影の画素でなく受光画素の有無で4区分の成立を見る。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`第5段階の検査点5

mod asset_preparation;

use super::error::距離区分の継ぎ目の検収エラー;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 継ぎ目を見る構図 {
    /// 5×5チャンクの検証用地形世界。既定であり、再配分の影響を受けない実用分割の側を守り続ける。
    検証用地形世界,
    /// 8km×10kmの大規模世界。明示境界25・100・1000・10000メートルの再配分が効く唯一の構図である。
    大規模世界,
}

impl 継ぎ目を見る構図 {
    pub(super) fn 引数を読む(引数一覧: &[String]) -> Result<Self, 距離区分の継ぎ目の検収エラー> {
        match 引数一覧 {
            [] => Ok(Self::検証用地形世界),
            [引数] if 引数 == "--large-world" => Ok(Self::大規模世界),
            _ => Err(距離区分の継ぎ目の検収エラー::引数が不正(引数一覧.join(" "))),
        }
    }

    /// 絵と由来の置き場。構図ごとに分けるのは、2つの構図の成果物が同じ名前で上書きし合わないためである。
    pub(super) fn 出力ディレクトリ(self) -> &'static str {
        match self {
            Self::検証用地形世界 => "target/csm_seam",
            Self::大規模世界 => "target/csm_seam_large_world",
        }
    }

    /// 人が読む構図の名前。由来と要約が名指し、成果物のディレクトリを取り違えられないようにする。
    pub(super) fn 呼び名(self) -> &'static str {
        match self {
            Self::検証用地形世界 => "検証用地形世界(5×5チャンク・箱の植生)",
            Self::大規模世界 => "大規模世界(8km×10km・遠景の固定構図)",
        }
    }

    /// 開く世界の綴りと時刻。由来がそのまま書き、人が絵と突き合わせられるようにする。
    pub(super) fn シーン名の綴り(self) -> &'static str {
        match self {
            Self::検証用地形世界 => super::run::検証用地形世界のシーン名の綴り,
            Self::大規模世界 => super::run::large_world_options::大規模世界のシーン名の綴り,
        }
    }

    pub(super) fn 一日内秒(self) -> &'static str {
        match self {
            Self::検証用地形世界 => super::run::検証用地形世界の一日内秒,
            Self::大規模世界 => super::run::large_world_options::大規模世界の一日内秒,
        }
    }

    /// この構図が要る影の距離区分の分け方。大規模世界だけが名指しの境界で走る。
    pub(super) fn 明示の境界を要るか(self) -> bool {
        match self {
            Self::検証用地形世界 => false,
            Self::大規模世界 => true,
        }
    }

    /// 輝度段差を距離区分の内側の勾配とも比べるか。真なら勾配比と絶対上限の両方を、偽なら絶対上限だけを課す。
    ///
    /// 勾配比の判定は「段差が地形の起伏に紛れるか」を測るものであり、箱の植生が大きな明暗を作る検証用地形世界に
    /// 合わせた形である。大規模世界の受光面は平坦で内側の勾配が0へ近づくため、比が発散して視認できない段差でも
    /// 落ちる構造的な偏りを持つ。実測では受光どうしの段差2.997階調に対し内側の勾配0.534であり比では落ちるが、
    /// 絶対上限12階調の4分の1であり親の目視でも識別できなかった(2026-08-16の裁定)。
    /// 段差の出どころ(区分1と区分2でシャドウマップ1テクセルが覆う長さが約12倍違い、低い太陽で受光面の
    /// 自己遮蔽量が変わる)は将来の改善材料として外部台帳へ起票済みであり、内訳は落ちても通っても記録する。
    pub(super) fn 内側の勾配と比べるか(self) -> bool {
        match self {
            Self::検証用地形世界 => true,
            Self::大規模世界 => false,
        }
    }

    /// 距離区分の成立を影の画素で見るか、受光画素で見るか。
    pub(super) fn 影の画素で四区分の成立を見るか(self) -> bool {
        match self {
            Self::検証用地形世界 => true,
            Self::大規模世界 => false,
        }
    }
}
