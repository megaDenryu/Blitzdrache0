//! 境界ごとに「影の画素が両側に実在するか」を数え、実在する境界だけを継ぎ目の判定の対象にする工程。
//! 受け取るのは距離区分の地図、返すのは境界ごとの実在の別と、判定の対象から外した理由の綴りである。
//!
//! 実在しない境界を対象から外すのは、境界の片側へ影が構造的に現れない構図があるためである。影の画素が0件の側へ
//! 「100件以上あること」を課すと、影が消えた退行と「もともと影が現れない」構図の区別がつかないまま落ちる。
//! 散布物を入れた大規模世界でも2つの境界が外れ、どちらも影の出どころの不足ではなく幾何から決まる(1000メートルの
//! 境界の奥側に散布物が無く、25メートルの境界の手前側は低い太陽が影を8.4メートル以上ずらす)。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「第6段階」
//!
//! **外したことを黙らない。** どの境界を、どちら側の影の画素が何件だったから外したのかを要約の行へ出す。
//! 出さないと、3つの境界のうち1つしか見ていない実行と3つとも見た実行が同じ「成功」に見える。
//!
//! **1つも残らなければ落とす。** 全部の境界を外した実行は継ぎ目を1つも見ていない。間引きは「その構図に
//! 影を落とす物が無い距離帯を対象から外す」ためのものであり、「影がどこにも無い絵を通す」ためのものではない。
//! 散布物を入れる前の大規模世界を正午で撮ると4距離区分とも影の画素0件になり、間引きだけを入れると検収が空になった。
//!
//! 4区分すべてに受光画素があることの判定はこの間引きを受けない。距離区分そのものが画面に現れているかは、
//! 影を落とす物があるかとは別の問いであり、どの構図でも課せる。

use super::super::band_map::距離区分の地図;
use super::super::{boundary, 境界の数, 近傍の幅};
use crate::acceptance::{判定の名前, 判定の破れ};

/// 境界1つの実在の別。実在するなら両側の影の画素数を持ち、しないなら数えた結果をそのまま持つ。
/// `間引く構図か`が偽の構図では、影が無くても判定の対象に残す。
pub(in crate::csm_seam) struct 境界の実在 {
    pub(in crate::csm_seam) 境界番号: usize,
    pub(in crate::csm_seam) 手前側の影画素数: usize,
    pub(in crate::csm_seam) 奥側の影画素数: usize,
    間引く構図か: bool, // 影が片側に1画素も無い境界を外す構図か
}

impl 境界の実在 {
    fn 影が両側にあるか(&self) -> bool {
        self.手前側の影画素数 > 0 && self.奥側の影画素数 > 0
    }

    /// 継ぎ目の判定を課す境界か。間引かない構図ではすべての境界が対象である。
    pub(in crate::csm_seam) fn 判定の対象か(&self) -> bool {
        !self.間引く構図か || self.影が両側にあるか()
    }
}

pub(in crate::csm_seam) fn 境界ごとに数える(地図: &距離区分の地図, 間引く構図か: bool) -> Vec<境界の実在> {
    (0..境界の数)
        .map(|境界番号| {
            let 近傍 = boundary::集める(地図, 境界番号, 1, 近傍の幅);
            境界の実在 {
                間引く構図か,
                境界番号,
                手前側の影画素数: 影の数(地図, &近傍.手前側),
                奥側の影画素数: 影の数(地図, &近傍.奥側),
            }
        })
        .collect()
}

/// 継ぎ目を見られる境界が1つも無ければ落とす。実測は境界ごとの両側の影の画素数をそのまま名指す。
pub(in crate::csm_seam) fn 継ぎ目を見られる境界があることを検査する(一覧: &[境界の実在]) -> Result<(), 判定の破れ> {
    if 一覧.iter().any(境界の実在::判定の対象か) {
        return Ok(());
    }
    Err(継ぎ目を見られる境界の判定名(一覧).あるはずのものが無い破れ())
}

fn 継ぎ目を見られる境界の判定名(一覧: &[境界の実在]) -> 判定の名前 {
    let 実測: Vec<String> = 一覧
        .iter()
        .map(|実在| format!("境界{}は手前{}奥{}", 実在.境界番号, 実在.手前側の影画素数, 実在.奥側の影画素数))
        .collect();
    判定の名前::組み立てた綴りから生成する(format!(
        "両側に影がある境界(境界ごとの影の画素数は{}である。この構図は影を1画素も出しておらず継ぎ目を見られない)",
        実測.join("・")
    ))
}

/// 判定の対象から外した境界を名指す1文。外した境界が無ければ、無かったことを述べる。
pub(in crate::csm_seam) fn 対象から外した境界の綴り(一覧: &[境界の実在]) -> String {
    let 外した: Vec<String> = 一覧
        .iter()
        .filter(|実在| !実在.判定の対象か())
        .map(|実在| {
            format!(
                "境界{}(手前側の影{}画素・奥側の影{}画素)",
                実在.境界番号, 実在.手前側の影画素数, 実在.奥側の影画素数
            )
        })
        .collect();
    if 外した.is_empty() {
        return "継ぎ目の判定から外した境界は無い".to_string();
    }
    format!("影が片側に1画素も無いため継ぎ目の判定から外した境界は{}", 外した.join("・"))
}

fn 影の数(地図: &距離区分の地図, 添字一覧: &[usize]) -> usize {
    添字一覧
        .iter()
        .filter(|&&添字| 地図.画素(添字 % 地図.幅, 添字 / 地図.幅).is_some_and(|画素| 画素.影の中))
        .count()
}
