//! 境界の輝度段差を、影の中の画素と受光している画素へ分けて測る工程。受け取るのは境界の両側の画素と本番の絵、
//! 返すのは内訳を述べる1文である。
//!
//! 混ぜた平均だけを見ると、段差が「影の描かれ方が両側で違う」ことによるのか「影の量が両側で違う」ことによるのかを
//! 区別できない。距離区分の継ぎ目が疑われたときに最初に要るのはこの区別であり、絵を開かずに読めるようにしておく。
//!
//! 影の中どうしがほぼ同じで受光どうしが離れていれば、影そのものは両側で同じに描けており、受光面の自己遮蔽の量が
//! 食い違っている。距離区分ごとにシャドウマップの1テクセルが覆う世界の長さが違うため、深度の偏りの効き方が変わり、
//! 低い太陽ではこの差が受光面の明るさへ出る。逆に影の中どうしが離れていれば、影の濃さそのものが両側で違う。

use super::super::band_map::距離区分の地図;
use super::super::run::輝度を求める;
use crate::acceptance::読み戻し画像;

pub(super) fn 内訳を述べる(地図: &距離区分の地図, 本番: &読み戻し画像, 手前側: &[usize], 奥側: &[usize]) -> String {
    let 受光 = 段差を測る(地図, 本番, 手前側, 奥側, false);
    let 影 = 段差を測る(地図, 本番, 手前側, 奥側, true);
    format!("受光どうしの段差{}・影の中どうしの段差{}", 綴る(受光), 綴る(影))
}

fn 綴る(段差: Option<f64>) -> String {
    段差.map_or_else(|| "は測る画素が無い".to_string(), |値| format!("{値:.3}"))
}

/// 片側でも該当する画素が無ければ測れない。0を返すと「段差が無い」と読めてしまうため無しで返す。
fn 段差を測る(
    地図: &距離区分の地図, 本番: &読み戻し画像, 手前側: &[usize], 奥側: &[usize], 影の中か: bool
) -> Option<f64> {
    let 手前 = 平均輝度(地図, 本番, 手前側, 影の中か)?;
    let 奥 = 平均輝度(地図, 本番, 奥側, 影の中か)?;
    Some((手前 - 奥).abs())
}

fn 平均輝度(地図: &距離区分の地図, 本番: &読み戻し画像, 添字一覧: &[usize], 影の中か: bool) -> Option<f64> {
    let 選んだ: Vec<usize> = 添字一覧
        .iter()
        .copied()
        .filter(|添字| 地図.画素(添字 % 地図.幅, 添字 / 地図.幅).is_some_and(|画素| 画素.影の中 == 影の中か))
        .collect();
    if 選んだ.is_empty() {
        return None;
    }
    let 数 = f64::from(u32::try_from(選んだ.len()).unwrap_or(u32::MAX));
    Some(選んだ.iter().map(|&添字| 輝度を求める(本番, 添字)).sum::<f64>() / 数)
}
