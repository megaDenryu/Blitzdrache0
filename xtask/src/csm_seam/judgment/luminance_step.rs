//! 境界の輝度段差の検査。受け取るのは距離区分の地図と本番の絵と境界の実在の一覧、返すのは境界ごとの実測である。
//!
//! 段差そのものは影の中も受光も混ぜた平均で測る。継ぎ目は絵の見た目の不連続であり、見る人は影と受光を分けて
//! 見ないためである。内訳は`step_breakdown`が別に測り、落ちたときも通ったときも記録へ残す。

use super::super::band_map::距離区分の地図;
use super::super::run::輝度を求める;
use super::super::{boundary, 段差の絶対上限, 近傍の幅};
use super::step_breakdown;
use super::verdict_names::{境界の近傍の判定名, 平均輝度を測る画素};
use super::境界の実在;
use crate::acceptance::{判定の破れ, 読み戻し画像};

/// 境界を挟む2つの距離区分の平均輝度の差を、絶対上限と、構図が求めるなら距離区分の内側の勾配とも比べる。
///
/// 勾配との比べは「段差が地形の起伏に紛れるか」を測るものであり、内側の勾配が大きい構図でだけ意味を持つ。
/// 平坦な受光面では勾配が0へ近づいて比が発散し、目に見えない段差でも落ちる。どの構図がこれを課すかは
/// `継ぎ目を見る構図::内側の勾配と比べるか`が持つ。内訳は課すか否かに依らず必ず測って記録へ残す。
pub(in crate::csm_seam) fn 実在する境界の輝度段差を検査する(
    地図: &距離区分の地図,
    本番: &読み戻し画像,
    一覧: &[境界の実在],
    内側の勾配と比べるか: bool,
) -> Result<Vec<境界の段差>, 判定の破れ> {
    let mut 実測 = Vec::new();
    for 境界番号 in 一覧.iter().filter(|実在| 実在.影が両側にあるか()).map(|実在| 実在.境界番号) {
        let 近傍 = boundary::集める(地図, 境界番号, 1, 近傍の幅);
        let 内側 = boundary::集める(地図, 境界番号, 近傍の幅 + 1, 近傍の幅 * 2);
        let 近傍手前 = 平均輝度(本番, &近傍.手前側)?;
        let 近傍奥 = 平均輝度(本番, &近傍.奥側)?;
        let 段差 = (近傍手前 - 近傍奥).abs();
        let 勾配 = (近傍手前 - 平均輝度(本番, &内側.手前側)?)
            .abs()
            .max((近傍奥 - 平均輝度(本番, &内側.奥側)?).abs());
        let 内訳 = step_breakdown::内訳を述べる(地図, 本番, &近傍.手前側, &近傍.奥側);
        if 内側の勾配と比べるか {
            境界の近傍の判定名(境界番号, &format!("輝度段差({内訳}。距離区分の内側の勾配との比べ)")).上限を課す(段差, 勾配)?;
        }
        境界の近傍の判定名(境界番号, &format!("輝度段差({内訳}。絶対上限との比べ)")).上限を課す(段差, 段差の絶対上限)?;
        実測.push(境界の段差 {
            境界番号,
            段差,
            内側の勾配: 勾配,
            内訳,
        });
    }
    Ok(実測)
}

/// 境界1つぶんの段差の実測。要約がそのまま読み上げるため、境界番号と内訳を一緒に持つ。
pub(in crate::csm_seam) struct 境界の段差 {
    pub(in crate::csm_seam) 境界番号: usize,
    pub(in crate::csm_seam) 段差: f64,
    pub(in crate::csm_seam) 内側の勾配: f64,
    pub(in crate::csm_seam) 内訳: String,
}

fn 平均輝度(本番: &読み戻し画像, 添字一覧: &[usize]) -> Result<f64, 判定の破れ> {
    if 添字一覧.is_empty() {
        return Err(平均輝度を測る画素.あるはずのものが無い破れ());
    }
    let 数 = f64::from(u32::try_from(添字一覧.len()).unwrap_or(u32::MAX));
    Ok(添字一覧.iter().map(|&添字| 輝度を求める(本番, 添字)).sum::<f64>() / 数)
}
