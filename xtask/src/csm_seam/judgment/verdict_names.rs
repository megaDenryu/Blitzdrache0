//! 判定が破れたときの文面の組み立て。受け取るのは破れた対象と同時に読ませたい実測値、返すのは判定の名前である。
//!
//! 名前へ距離区分別の実測を丸ごと入れるのは、1つの距離区分が空だったときに他の距離区分の数も同じ行で読めるようにするためである。
//! 空でない距離区分の数が分かると、構図が全体としてずれているのか1つの距離区分だけが現れていないのかをその場で切り分けられる。

use crate::acceptance::判定の名前;

/// 境界が画面に現れていない構図では、この画素が1つも集まらない。
pub(super) const 平均輝度を測る画素: 判定の名前 = 判定の名前::定数から生成する("平均輝度を測る画素");

pub(super) fn 距離区分の影の画素の判定名(距離区分: usize, 距離区分別の影画素数: [usize; 4]) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "距離区分{距離区分}の影の画素(距離区分別の影画素数は{距離区分別の影画素数:?}である)"
    ))
}

pub(super) fn 距離区分の受光画素の判定名(距離区分: usize, 距離区分別の受光画素数: [usize; 4]) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "距離区分{距離区分}の受光画素(距離区分別の受光画素数は{距離区分別の受光画素数:?}である)"
    ))
}

pub(super) fn 境界の近傍の判定名(境界番号: usize, 測るもの: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("境界{境界番号}と{}の近傍の{測るもの}", 境界番号 + 1))
}
