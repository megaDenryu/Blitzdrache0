//! アプリが起動時に出す「影の距離区分の分け方」の行を読み、構図が要る分け方で走ったことを確かめる工程。
//! 受け取るのは終了時報告と構図、返すのは読み取った1文か契約の破れである。
//!
//! この行を読むのは、再配分が実際に効いたかを絵から確かめられないためである。分け方が実用分割のままでも
//! 4つの距離区分は現れ、境界の段差も出る。判定はどちらでも通ってしまい、「再配分を検収したつもりで
//! 再配分前の絵を見ていた」ことに誰も気づかない。分け方は行にしか現れないので、行で確かめる。
//!
//! 注意: 見出しの綴りは`crates/blitz_app/src/reports/shadow_band_assignment.rs`との契約であり、
//! `cargo xtask conform`の綴りの台帳が両側を結んでいる。

use super::composition::継ぎ目を見る構図;
use crate::acceptance::{判定の名前, 判定の破れ, 終了時報告};
use crate::report_heading::報告の見出し;

const 分け方の見出し: 報告の見出し = 報告の見出し::定数から生成する("影の距離区分の分け方:");
/// 明示の境界で分けて走ったときに行の先頭へ出る呼び名。
const 明示境界の呼び名: &str = "明示境界";
const 分け方の契約: 判定の名前 = 判定の名前::定数から生成する("構図が要る影の距離区分の分け方で走ったこと");

pub(super) fn 読んで課す(報告: &終了時報告, 構図: 継ぎ目を見る構図) -> Result<String, 判定の破れ> {
    let 本文 = 報告
        .見出しに続く本文(&分け方の見出し)
        .map_err(|_| 分け方の契約.あるはずのものが無い破れ())?;
    let 明示境界で走った = 本文.trim_start().starts_with(明示境界の呼び名);
    分け方の契約.真であることを課す(明示境界で走った == 構図.明示の境界を要るか())?;
    Ok(本文.trim().to_string())
}
