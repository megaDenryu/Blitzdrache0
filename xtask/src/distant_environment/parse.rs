//! 遠方環境報告の全文から、判定に要る行だけを取り出す工程。受け取るのは終了時報告、返すのは行の値を組んだ報告である。
//!
//! 行の形をここが単独で持つのは、これがblitz_appとxtaskの間の機械可読な契約そのものだからである。
//! 報告側へ項目を足すときに直す場所が1つになる。語の並びに依存せず鍵で参照するのは、報告へ項目を足したときに読み取り側が壊れないようにするためである。行の値の取り出しは`field`が持つ。

pub(crate) mod field;

use field::{実数値, 整数値, 添字値, 語句値};

use crate::acceptance::{報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;

/// 鍵の判定の1行。条件の名前とそのときの指示である。
pub(super) struct 鍵行 {
    pub(super) 条件: String,
    pub(super) 指示: String,
}

/// 代表テクセルの1行。期待と実測の3成分を持つ。
pub(super) struct 代表行 {
    pub(super) 層: u32,
    pub(super) 横: u32,
    pub(super) 縦: u32,
    pub(super) 期待: [f64; 3],
    pub(super) 実測: [f64; 3],
}

pub(super) struct 報告 {
    pub(super) 検証の状況: String,
    pub(super) 検証件数: usize,
    pub(super) 円盤対照の不一致: usize,
    pub(super) テクセル数: usize,
    pub(super) 非有限: usize,
    pub(super) 負: usize,
    pub(super) 予約が非零: usize,
    pub(super) 面境界の最大相対差: f64,
    pub(super) 鍵一覧: Vec<鍵行>,
    pub(super) 代表一覧: Vec<代表行>,
}

const 鍵の見出し: 報告の見出し = 報告の見出し::定数から生成する("遠方環境鍵");
const 検証層の見出し: 報告の見出し = 報告の見出し::定数から生成する("検証層");
const 円盤対照の見出し: 報告の見出し = 報告の見出し::定数から生成する("遠方環境円盤対照");
const 統計の見出し: 報告の見出し = 報告の見出し::定数から生成する("遠方環境統計");
const 面境界の見出し: 報告の見出し = 報告の見出し::定数から生成する("遠方環境面境界");
const 代表の見出し: 報告の見出し = 報告の見出し::定数から生成する("遠方環境代表");

pub(super) fn 報告を取り出す(終了時の報告: &終了時報告) -> Result<報告, 検収エラー> {
    let 検証層 = 終了時の報告.見出しの1行(&検証層の見出し)?;
    let 統計 = 終了時の報告.見出しの1行(&統計の見出し)?;
    Ok(報告 {
        検証の状況: 語句値(&検証層, "状況")?,
        検証件数: 整数値(&検証層, "件数")?,
        円盤対照の不一致: 整数値(&終了時の報告.見出しの1行(&円盤対照の見出し)?, "不一致")?,
        テクセル数: 整数値(&統計, "テクセル数")?,
        非有限: 整数値(&統計, "非有限")?,
        負: 整数値(&統計, "負")?,
        予約が非零: 整数値(&統計, "予約が非零")?,
        面境界の最大相対差: 実数値(&終了時の報告.見出しの1行(&面境界の見出し)?, "最大相対差")?,
        鍵一覧: 鍵の一覧を読む(終了時の報告)?,
        代表一覧: 代表の一覧を読む(終了時の報告)?,
    })
}

fn 鍵の一覧を読む(終了時の報告: &終了時報告) -> Result<Vec<鍵行>, 検収エラー> {
    終了時の報告.見出しで始まる行の一覧(&鍵の見出し).iter().map(鍵行を読む).collect()
}

fn 鍵行を読む(行: &報告の行) -> Result<鍵行, 検収エラー> {
    Ok(鍵行 {
        条件: 語句値(行, "条件")?,
        指示: 語句値(行, "指示")?,
    })
}

fn 代表の一覧を読む(終了時の報告: &終了時報告) -> Result<Vec<代表行>, 検収エラー> {
    終了時の報告.見出しで始まる行の一覧(&代表の見出し).iter().map(代表行を読む).collect()
}

fn 代表行を読む(行: &報告の行) -> Result<代表行, 検収エラー> {
    Ok(代表行 {
        層: 添字値(行, "層")?,
        横: 添字値(行, "横")?,
        縦: 添字値(行, "縦")?,
        期待: [実数値(行, "期待赤")?, 実数値(行, "期待緑")?, 実数値(行, "期待青")?],
        実測: [実数値(行, "実測赤")?, 実数値(行, "実測緑")?, 実数値(行, "実測青")?],
    })
}
