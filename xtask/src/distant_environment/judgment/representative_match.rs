//! 代表テクセルとCPU正本の突き合わせ。受け取るのは代表テクセルの行の一覧、返すのは最大の相対誤差か
//! 最初に許容を超えた場所である。
//!
//! 期待の絶対値が小さい成分を相対誤差で見ないのは、分母が0に近いと相対誤差が発散するためである。

use super::super::parse::代表行;
use super::super::thresholds::{代表の相対許容, 代表の絶対許容};
use crate::acceptance::{判定の名前, 判定の破れ};

const 代表の行: 判定の名前 = 判定の名前::定数から生成する("遠方環境代表の行");

/// 代表テクセルの全成分をCPU正本と突き合わせ、最大の相対誤差を返す。
/// 期待の絶対値が小さい成分は相対誤差でなく絶対誤差で見る。分母が0に近いと相対誤差が発散するためである。
pub(super) fn 代表テクセルを検査する(代表一覧: &[代表行]) -> Result<f64, 判定の破れ> {
    if 代表一覧.is_empty() {
        return Err(代表の行.あるはずのものが無い破れ());
    }
    let mut 最大相対誤差 = 0.0_f64;
    for 行 in 代表一覧 {
        for 添字 in 0..3 {
            let 期待 = 行.期待[添字];
            let 差 = (期待 - 行.実測[添字]).abs();
            if 期待.abs() <= 代表の絶対許容 {
                場所つきの判定名(行, 添字, "絶対").上限を課す(差, 代表の絶対許容)?;
                continue;
            }
            let 相対 = 差 / 期待.abs();
            場所つきの判定名(行, 添字, "相対").上限を課す(相対, 代表の相対許容)?;
            最大相対誤差 = 最大相対誤差.max(相対);
        }
    }
    Ok(最大相対誤差)
}

fn 場所つきの判定名(行: &代表行, 添字: usize, 種別: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("遠方環境代表(層{} 横{} 縦{} 成分{添字})の{種別}誤差", 行.層, 行.横, 行.縦))
}
