//! 遠方環境報告の全項目の判定。受け取るのは読み取った報告、返すのは判定の要約か最初に見つけた違反である。
//!
//! 見るのは6つである。鍵の判定の並び・validationの指摘・円盤対照のバイト一致・全テクセルの健全性・
//! 代表テクセルのCPU正本との一致・面境界の連続性である。

mod representative_match;

use representative_match::代表テクセルを検査する;

use super::parse::報告;
use super::thresholds::{期待する鍵の並び, 検証層が有効な語, 面境界の相対許容};
use crate::acceptance::{判定の名前, 判定の破れ};

const 鍵の判定の行数: 判定の名前 = 判定の名前::定数から生成する("鍵の判定の行数");
const 円盤対照で動いたテクセル: 判定の名前 =
    判定の名前::定数から生成する("太陽円盤放射輝度だけを変えた対で動いた遠方環境のテクセル(円盤を二重に計上している)");
const 遠方環境のテクセル: 判定の名前 = 判定の名前::定数から生成する("遠方環境のテクセル");
const 面境界の最大相対差: 判定の名前 = 判定の名前::定数から生成する("遠方環境の面境界の最大相対差");

pub(super) struct 判定 {
    pub(super) 代表テクセル数: usize,
    pub(super) 最大相対誤差: f64,
    pub(super) 検証の告知: String,
}

pub(super) fn 全項目を検査する(報告: &報告) -> Result<判定, 判定の破れ> {
    鍵の並びを検査する(報告)?;
    let 検証の告知 = 検証を検査する(報告)?;
    円盤対照で動いたテクセル.零件であることを課す(報告.円盤対照の不一致)?;
    健全性を検査する(報告)?;
    面境界の最大相対差.上限を課す(報告.面境界の最大相対差, 面境界の相対許容)?;
    let 最大相対誤差 = 代表テクセルを検査する(&報告.代表一覧)?;
    Ok(判定 {
        代表テクセル数: 報告.代表一覧.len(),
        最大相対誤差,
        検証の告知,
    })
}

fn 鍵の並びを検査する(報告: &報告) -> Result<(), 判定の破れ> {
    鍵の判定の行数.一致を課す(報告.鍵一覧.len(), 期待する鍵の並び.len())?;
    for (番号, (行, (条件, 指示))) in 報告.鍵一覧.iter().zip(期待する鍵の並び).enumerate() {
        判定名を組む(&format!("鍵の判定の{}件目の条件", 番号 + 1)).綴りの一致を課す(&行.条件, 条件)?;
        判定名を組む(&format!("条件{条件}の指示")).綴りの一致を課す(&行.指示, 指示)?;
    }
    Ok(())
}

/// 層が無い機材の0件を有効な機材の0件と読み違えないよう、状況の語を告知へ載せる。
fn 検証を検査する(報告: &報告) -> Result<String, 判定の破れ> {
    判定名を組む(&format!("validation層の指摘(状況={})", 報告.検証の状況)).零件であることを課す(報告.検証件数)?;
    if 報告.検証の状況 != 検証層が有効な語 {
        return Ok(format!("validation層は{}のため指摘0件は保証にならない", 報告.検証の状況));
    }
    Ok("validation層は有効で指摘0件だった".to_string())
}

fn 健全性を検査する(報告: &報告) -> Result<(), 判定の破れ> {
    if 報告.テクセル数 == 0 {
        return Err(遠方環境のテクセル.あるはずのものが無い破れ());
    }
    let 破れ一覧 = [("非有限", 報告.非有限), ("負", 報告.負), ("4成分目が非零", 報告.予約が非零)];
    for (名前, 件数) in 破れ一覧 {
        判定名を組む(&format!("遠方環境の{名前}のテクセル")).零件であることを課す(件数)?;
    }
    Ok(())
}

fn 判定名を組む(綴り: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(綴り.to_string())
}
