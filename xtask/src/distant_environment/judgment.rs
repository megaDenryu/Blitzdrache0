//! 遠方環境報告の全項目の判定。受け取るのは読み取った報告、返すのは判定の要約か最初に見つけた違反である。
//!
//! 見るのは6つである。鍵の判定の並び・validationの指摘・円盤対照のバイト一致・全テクセルの健全性・
//! 代表テクセルのCPU正本との一致・面境界の連続性である。

mod representative_match;

use representative_match::代表テクセルを検査する;

use super::parse::報告;
use super::thresholds::{期待する鍵の並び, 検証層が有効な語, 面境界の相対許容};

pub(super) struct 判定 {
    pub(super) 代表テクセル数: usize,
    pub(super) 最大相対誤差: f64,
    pub(super) 検証の告知: String,
}

pub(super) fn 全項目を検査する(報告: &報告) -> Result<判定, String> {
    鍵の並びを検査する(報告)?;
    let 検証の告知 = 検証を検査する(報告)?;
    if 報告.円盤対照の不一致 != 0 {
        return Err(format!(
            "太陽円盤放射輝度だけを変えた対で遠方環境が{}テクセル動いた(円盤を二重に計上している)",
            報告.円盤対照の不一致
        ));
    }
    健全性を検査する(報告)?;
    if 報告.面境界の最大相対差 > 面境界の相対許容 {
        return Err(format!(
            "面境界の最大相対差{:.3e}が許容{面境界の相対許容:.1e}を超えた",
            報告.面境界の最大相対差
        ));
    }
    let 最大相対誤差 = 代表テクセルを検査する(&報告.代表一覧)?;
    Ok(判定 {
        代表テクセル数: 報告.代表一覧.len(),
        最大相対誤差,
        検証の告知,
    })
}

fn 鍵の並びを検査する(報告: &報告) -> Result<(), String> {
    if 報告.鍵一覧.len() != 期待する鍵の並び.len() {
        return Err(format!(
            "鍵の判定の行数が{}件で、期待する{}件と違う",
            報告.鍵一覧.len(),
            期待する鍵の並び.len()
        ));
    }
    for (番号, (行, (条件, 指示))) in 報告.鍵一覧.iter().zip(期待する鍵の並び).enumerate() {
        if 行.条件 != 条件 {
            return Err(format!("鍵の判定の{}件目の条件が{}で、期待する{条件}と違う", 番号 + 1, 行.条件));
        }
        if 行.指示 != 指示 {
            return Err(format!("条件{条件}の指示が{}で、期待する{指示}と違う", 行.指示));
        }
    }
    Ok(())
}

/// 層が無い機材の0件を有効な機材の0件と読み違えないよう、状況の語を告知へ載せる。
fn 検証を検査する(報告: &報告) -> Result<String, String> {
    if 報告.検証件数 != 0 {
        return Err(format!("validation層が{}件の指摘を出した(状況={})", 報告.検証件数, 報告.検証の状況));
    }
    if 報告.検証の状況 != 検証層が有効な語 {
        return Ok(format!("validation層は{}のため指摘0件は保証にならない", 報告.検証の状況));
    }
    Ok("validation層は有効で指摘0件だった".to_string())
}

fn 健全性を検査する(報告: &報告) -> Result<(), String> {
    if 報告.テクセル数 == 0 {
        return Err("遠方環境のテクセル数が0である".to_string());
    }
    let 破れ一覧 = [("非有限", 報告.非有限), ("負", 報告.負), ("4成分目が非零", 報告.予約が非零)];
    for (名前, 件数) in 破れ一覧 {
        if 件数 != 0 {
            return Err(format!("遠方環境に{名前}のテクセルが{件数}件あった"));
        }
    }
    Ok(())
}
