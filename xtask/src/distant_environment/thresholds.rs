//! 遠方環境の判定に使う許容と期待の台帳。担当するのは値だけであり、判定の手順は`judgment`が持つ。
//!
//! 代表テクセルの許容が半精度の丸め(相対4.9e-4まで)より大きいのは、遠方環境の1テクセルが
//! 半精度で保持されたスカイビューの表を双一次補間で参照し、その結果をもう一度半精度で書くためである。
//! 丸めが2回入るうえ、補間の重みが4つのテクセルの丸め誤差を混ぜる。
//! 2026-08-03の実測の最大は相対1.9e-3であり、許容はその約2.6倍の安全幅を取った値である。

/// 代表テクセルのCPU正本との相対誤差の許容。
pub(super) const 代表の相対許容: f64 = 5.0e-3;

/// ほぼ0の域で相対誤差の代わりに見る絶対誤差の許容。分母が小さいと相対誤差が発散するためである。
pub(super) const 代表の絶対許容: f64 = 1.0e-6;

/// 面境界で向かい合うテクセルの値の相対差の許容。2つは半テクセルぶん離れた別々の向きを標本するため
/// 厳密には一致しない。天空放射輝度が向きについて連続であることから、1テクセルぶんの角の中での変化に収まる。
///
/// 側面の4本だけを見ていたときの実測は3.97e-3、天頂と天底の面を含む12本すべてを見るようにした後の実測は
/// 2.096e-2である。上下の面の稜線が大きいのは、側面どうしの稜線が方位だけ違う向きを突き合わせるのに対し、
/// 上下の面の稜線が高度の違う向きを突き合わせるためである。天空放射輝度は方位より高度に対して速く変わり、
/// 太陽の前方散乱が強い高度をまたぐ稜線で差が最大になる。許容はその約2.4倍の安全幅を取った値である。
/// 対応そのものの正しさは、値でなく向きの角度で見る`reports::cube_seam`のユニットテストが担う。
pub(super) const 面境界の相対許容: f64 = 5.0e-2;

/// 鍵の判定が返すべき指示の並び。条件の名前と指示の語の組であり、報告の行と順序まで一致しなければならない。
/// 太陽方位のみ変更で焼き直さないことと、明るさの2値の変更で焼き直すことが設計の主張そのものである。
pub(super) const 期待する鍵の並び: [(&str, &str); 6] = [
    ("初回", "焼き直す"),
    ("同一条件", "前の結果を使う"),
    ("太陽方位のみ変更", "前の結果を使う"),
    ("太陽高度変更", "焼き直す"),
    ("太陽放射照度変更", "焼き直す"),
    ("夜空放射輝度変更", "焼き直す"),
];

/// validation層が有効だったことを表す語。これ以外の語では件数0が保証にならないため、その事実を告知する。
pub(super) const 検証層が有効な語: &str = "有効";
