//! 報告の1行から鍵に結ばれた値を取り出す工程。受け取るのは報告の行と鍵の綴り、返すのは語句・整数・実数・添字である。
//! 語の並びに依存せず鍵で参照するのは、報告へ項目を足したときに読み取り側が壊れないようにするためである。
//! 派生表現の検収も同じ形の行を読むため、この工程を共有する。

use crate::acceptance::{報告の行, 検収エラー};
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

/// この2つの報告の行は全項目が「鍵=値」の形で空白区切りに並ぶ。
const 値の結ばれ方: 鍵に値が結ばれる形 = 鍵に値が結ばれる形::等号の後ろが値である;

pub(crate) fn 語句値(行: &報告の行, 鍵: &str) -> Result<String, 検収エラー> {
    行.鍵に結ばれた綴り(&鍵を組む(鍵), 値の結ばれ方)
}

pub(crate) fn 整数値(行: &報告の行, 鍵: &str) -> Result<usize, 検収エラー> {
    行.鍵に結ばれた数(&鍵を組む(鍵), 値の結ばれ方)
}

pub(crate) fn 実数値(行: &報告の行, 鍵: &str) -> Result<f64, 検収エラー> {
    行.鍵に結ばれた数(&鍵を組む(鍵), 値の結ばれ方)
}

/// 立方体の層や段のように、面の一辺より小さい範囲にしか入らない添字。
pub(crate) fn 添字値(行: &報告の行, 鍵: &str) -> Result<u32, 検収エラー> {
    行.鍵に結ばれた数(&鍵を組む(鍵), 値の結ばれ方)
}

fn 鍵を組む(綴り: &str) -> 報告の行の鍵 {
    報告の行の鍵::組み立てた綴りから生成する(綴り.to_string())
}
