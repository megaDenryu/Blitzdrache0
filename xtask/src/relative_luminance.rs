//! 圧縮前のHDRカラーから相対輝度を求める工程。受け取るのは1画素の成分列、返すのはその相対輝度である。
//!
//! 入口ごとに重みを持たないのは、明るさの分布を実測する入口と段差を測る入口が同じ輝度の定義を読むためである。
//! 片方だけが重みを変えると、制定したヒストグラムの範囲と段差の尺度が別の明るさを指す。
//!
//! 正本は`crates/blitz_engine/src/auto_exposure/luminance.rs`にある。xtaskは外部クレートへ依存しない方針のため
//! 正本を読めず、値を持ち直している。この二重定義は`cargo xtask conform`の定数一致検査へ登録してある。
//!
//! 積の順と丸めの回数を正本と揃えないのは、ここが要求するのが「同じ明るさの定義」までであり、
//! CPUとGPUでビンが1つもずれない一致契約は自動露出の検収が別に持つためである。

const 赤の重み: f64 = 0.2126;
const 緑の重み: f64 = 0.7152;
const 青の重み: f64 = 0.0722;

/// 相対輝度Y = 0.2126R + 0.7152G + 0.0722B(BT.709の係数)。単位系は入力の線形放射輝度のままである。
pub fn 相対輝度(画素: &[f32]) -> f64 {
    f64::from(画素[0]) * 赤の重み + f64::from(画素[1]) * 緑の重み + f64::from(画素[2]) * 青の重み
}
