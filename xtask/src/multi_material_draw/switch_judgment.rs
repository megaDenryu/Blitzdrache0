//! 記録側の切替の判定。触れるのは2つの計数報告の記録側の3つの数だけであり、画素にも束縛回数にも触れない。
//!
//! シーンのパイプライン切替が材質の数で増えないことと、材質切替が描いた材質の数と一致することをここで固定する。
//! 材質を2件に分けてもパイプラインが1本のままであることが「材質IDをパイプラインキーへ混ぜていない」ことの実行の値による証拠であり、
//! 材質切替が材質の数と一致することが、整列で同じ材質の発行が連続していることの証拠である
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段6の検収ゲート(v))。

use crate::report_parse::計数報告;

/// 布を持たないこの検収入口では、シーンパスで束縛するパイプラインは材質描画族の1本だけである。
const シーンのパイプライン切替: u64 = 1;

pub(super) fn 記録側の切替を検査する(二材質: &計数報告, 単一材質: &計数報告) -> Result<(), String> {
    for (名前, 計数, 材質の数) in [("2材質", 二材質, 2), ("1材質", 単一材質, 1)] {
        if 計数.シーン.パイプライン切替 != シーンのパイプライン切替 {
            return Err(format!(
                "{名前}のシーンパスのパイプライン切替が{}回で、期待する{シーンのパイプライン切替}回と違う",
                計数.シーン.パイプライン切替
            ));
        }
        if 計数.シーン.材質切替 != 材質の数 {
            return Err(format!(
                "{名前}のシーンパスの材質切替が{}回で、描いた材質の数{材質の数}と違う(整列で同じ材質が連続していない疑い)",
                計数.シーン.材質切替
            ));
        }
        描画数が発行数と一致することを確かめる(名前, 計数)?;
        シャドウが材質切替を数えないことを確かめる(名前, 計数)?;
    }
    Ok(())
}

/// 発行数は作業領域が積んだ件数、描画数は記録が`vkCmdDrawIndexed`を呼んだ回数である。観測地点が違う2つが一致することが、
/// 記録の経路が発行を落としても二重に積んでもいないことの証拠になる。布を持たないこの入口ではシーンパスの描画が全部この発行から出る。
fn 描画数が発行数と一致することを確かめる(名前: &str, 計数: &計数報告) -> Result<(), String> {
    for (パス名, パス) in crate::report_parse::全パスを並べる(計数) {
        if パス.描画数 != パス.発行数 {
            return Err(format!("{名前}の{パス名}で描画数{}が発行数{}と一致しない", パス.描画数, パス.発行数));
        }
    }
    Ok(())
}

/// シャドウ記録は材質のセットも材質レコードも読まないため、材質切替を1回も数えない。
fn シャドウが材質切替を数えないことを確かめる(名前: &str, 計数: &計数報告) -> Result<(), String> {
    for (番号, パス) in 計数.距離区分別のシャドウ.iter().enumerate() {
        if パス.材質切替 != 0 {
            return Err(format!("{名前}のシャドウ距離区分{番号}が材質切替を{}回数えた", パス.材質切替));
        }
    }
    Ok(())
}
