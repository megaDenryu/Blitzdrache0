//! 読み戻し画像の左右の板から代表色を採る工程。受け取るのは画像、返すのは左右それぞれの平均RGBである。
//!
//! 領域を画面の割合で決めるのは、読み戻し画像の寸法がウィンドウの大きさで変わるためである。割合を千分率の整数で持つのは、
//! 小数から画素位置を出すと丸めの向きを別に決める必要が出るためであり、掛けてから割れば向きが1つに定まる。
//! 板は原点を挟んで左右に置かれ、既定カメラの縦視野60度・距離3メートル・16対9の画面では
//! 左の板が画面の横0.31から0.48、右の板が0.52から0.69、縦は両方とも0.33から0.67を占める。
//! 判定領域はその内側へ十分に寄せてあり、板の縁と中央の隙間を含まない。

use crate::vegetation_run::実行結果;

const 左の板の横千分率: (usize, usize) = (350, 450);
const 右の板の横千分率: (usize, usize) = (550, 650);
const 板の縦千分率: (usize, usize) = (420, 580);

/// 平均RGB。1画素ずつの丸め誤差を持ち込まないよう、各成分の合計を画素数で割った値を持つ。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 代表色 {
    pub(super) 赤: u64,
    pub(super) 緑: u64,
    pub(super) 青: u64,
}

pub(super) struct 左右の代表色 {
    pub(super) 左: 代表色,
    pub(super) 右: 代表色,
}

pub(super) fn 左右の代表色を採る(画像: &実行結果) -> Result<左右の代表色, String> {
    Ok(左右の代表色 {
        左: 平均色を採る(画像, 左の板の横千分率)?,
        右: 平均色を採る(画像, 右の板の横千分率)?,
    })
}

fn 平均色を採る(画像: &実行結果, 横千分率: (usize, usize)) -> Result<代表色, String> {
    let x開始 = 千分率を画素へ(画像.幅, 横千分率.0);
    let x終端 = 千分率を画素へ(画像.幅, 横千分率.1);
    let y開始 = 千分率を画素へ(画像.高さ, 板の縦千分率.0);
    let y終端 = 千分率を画素へ(画像.高さ, 板の縦千分率.1);
    let 画素数 = u64::try_from((x終端 - x開始) * (y終端 - y開始)).unwrap_or(0);
    if 画素数 == 0 {
        return Err(format!("判定領域が空である: 読み戻し画像{}×{}", 画像.幅, 画像.高さ));
    }
    let (mut 赤, mut 緑, mut 青) = (0u64, 0u64, 0u64);
    for y in y開始..y終端 {
        for x in x開始..x終端 {
            let 先頭 = (y * 画像.幅 + x) * 4;
            赤 += u64::from(画像.rgba8[先頭]);
            緑 += u64::from(画像.rgba8[先頭 + 1]);
            青 += u64::from(画像.rgba8[先頭 + 2]);
        }
    }
    Ok(代表色 {
        赤: 赤 / 画素数,
        緑: 緑 / 画素数,
        青: 青 / 画素数,
    })
}

fn 千分率を画素へ(全体: usize, 千分率: usize) -> usize {
    (全体.saturating_mul(千分率) / 1000).min(全体)
}
