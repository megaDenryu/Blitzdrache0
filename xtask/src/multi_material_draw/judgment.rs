//! 2材質のシーンと1材質の対照に対する画素の判定。受け取るのは2回の実行の代表色、返すのは合否である。
//!
//! 判定は2つである。2材質のシーンで左右の板が別の色に塗られることと、1材質の対照で左右の色が一致することである。
//! 後者が要るのは、左右の色が違うのが材質の違いによるものであり、位置や光の当たり方によるものでないことの根拠だからである。
//! 計数の突き合わせは`count_judgment`が持つ。

use crate::plate_region::左右の代表色;

/// 左右の代表色が別の材質だと言えるための、対応する成分の差の下限。ベースカラー係数の差はこれよりはるかに大きいため、
/// この下限は「わずかな陰影の違い」と「別の材質」を分ける値として置く。
const 成分差の下限: u64 = 40;

pub(super) fn 二材質の画素を検査する(色: &左右の代表色) -> Result<(), String> {
    if 色.左.赤 < 色.右.赤 + 成分差の下限 {
        return Err(format!("左の板が赤の材質として読めない: 左の赤{}、右の赤{}", 色.左.赤, 色.右.赤));
    }
    if 色.右.青 < 色.左.青 + 成分差の下限 {
        return Err(format!("右の板が青の材質として読めない: 左の青{}、右の青{}", 色.左.青, 色.右.青));
    }
    Ok(())
}

pub(super) fn 単一材質の画素を検査する(色: &左右の代表色) -> Result<(), String> {
    if 色.左 != 色.右 {
        return Err(format!("1材質の対照で左右の板の色が違う: 左{:?}、右{:?}", 色.左, 色.右));
    }
    Ok(())
}
