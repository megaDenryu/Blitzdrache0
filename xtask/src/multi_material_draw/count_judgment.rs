//! 2材質と1材質の計数を突き合わせる規則。触れるのは2つの計数報告だけであり、画素にも絵の書き出しにも触れない。
//! 材質を分けたときに増えてよい数(発行数・ジオメトリのセットの束縛)と、変わってはならない数(可視数・個体数・
//! 材質のセットの束縛・常駐画像枚数)をここが1箇所で決める。

use crate::report_parse::計数報告;

/// 発行数はプリミティブの数ぶん増え、可視ID数とシーン可視数は変わらない。
pub(super) fn 計数を検査する(二材質: &計数報告, 単一材質: &計数報告) -> Result<(), String> {
    crate::count_consistency::計数の整合を検査する("multi-material-draw(2材質)", 二材質)?;
    crate::count_consistency::計数の整合を検査する("multi-material-draw(1材質)", 単一材質)?;
    if 二材質.シーン.発行数 != 単一材質.シーン.発行数 + 1 {
        return Err(format!(
            "シーンパスの発行数がプリミティブ1件ぶん増えていない: 2材質{}回、1材質{}回",
            二材質.シーン.発行数, 単一材質.シーン.発行数
        ));
    }
    可視の数が変わらないことを確かめる(二材質, 単一材質)?;
    材質のセットの束縛が増えないことを確かめる(二材質, 単一材質)?;
    正準フォールバックが材質で複製されないことを確かめる(二材質, 単一材質)?;
    for (名前, 計数) in [("2材質", 二材質), ("1材質", 単一材質)] {
        if 計数.validation件数 != 0 {
            return Err(format!("{名前}の実行でvalidationが{}件発生した", 計数.validation件数));
        }
    }
    Ok(())
}

/// テクスチャを1枚も持たない材質だけのシーンでは、常駐する画像は世代で共有する正準フォールバックの3枚だけである。
/// 材質が1件から2件へ増えても3枚のままであることが、無しの材質が材質ごとの既定の画素を持たないことの実配線の証拠になる
/// (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段4bの検収ゲート(ii))。
fn 正準フォールバックが材質で複製されないことを確かめる(
    二材質: &計数報告, 単一材質: &計数報告
) -> Result<(), String> {
    let 正準フォールバックの枚数 = 3;
    for (名前, 計数, 期待する材質件数) in [("2材質", 二材質, 2), ("1材質", 単一材質, 1)] {
        if 計数.材質件数 != 期待する材質件数 {
            return Err(format!(
                "{名前}の資源表世代の材質件数が{}件で、期待する{期待する材質件数}件と違う",
                計数.材質件数
            ));
        }
        if 計数.常駐画像枚数 != 正準フォールバックの枚数 {
            return Err(format!(
                "{名前}の常駐画像枚数が{}枚で、正準フォールバックの{正準フォールバックの枚数}枚に収まっていない",
                計数.常駐画像枚数
            ));
        }
    }
    Ok(())
}

/// 材質のセット(番号2)はパスごと1回であり、材質もプリミティブも増えた2材質の側でも回数が変わらない。
/// ジオメトリのセット(番号1)は発行ごとに結ぶため、こちらは増えることを同時に確かめて、計器が動いていることも見る
/// (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段4bの検収ゲート(iii))。
fn 材質のセットの束縛が増えないことを確かめる(二材質: &計数報告, 単一材質: &計数報告) -> Result<(), String> {
    let 材質のセット番号 = 2usize;
    let ジオメトリのセット番号 = 1usize;
    for (名前, 計数) in [("2材質", 二材質), ("1材質", 単一材質)] {
        let 回数 = 計数
            .セット別束縛回数
            .get(材質のセット番号)
            .copied()
            .ok_or_else(|| format!("{名前}の報告にセット番号{材質のセット番号}の束縛回数が無い"))?;
        if 回数 != 1 {
            return Err(format!("{名前}で材質のセットの束縛が1回でなく{回数}回だった"));
        }
    }
    let 二材質のジオメトリ = 二材質.セット別束縛回数.get(ジオメトリのセット番号).copied().unwrap_or(0);
    let 単一材質のジオメトリ = 単一材質.セット別束縛回数.get(ジオメトリのセット番号).copied().unwrap_or(0);
    if 二材質のジオメトリ <= 単一材質のジオメトリ {
        return Err(format!(
            "ジオメトリのセットの束縛がプリミティブの数で増えていない(計器が動いていない疑い): 2材質{二材質のジオメトリ}回、1材質{単一材質のジオメトリ}回"
        ));
    }
    Ok(())
}

fn 可視の数が変わらないことを確かめる(二材質: &計数報告, 単一材質: &計数報告) -> Result<(), String> {
    if 二材質.シーン.可視数 != 単一材質.シーン.可視数 || 二材質.シーン.個体数 != 単一材質.シーン.個体数 {
        return Err(format!(
            "材質を分けるとシーンパスの可視数か個体数が変わった: 2材質は可視{}・個体{}、1材質は可視{}・個体{}",
            二材質.シーン.可視数, 二材質.シーン.個体数, 単一材質.シーン.可視数, 単一材質.シーン.個体数
        ));
    }
    if 二材質.可視個体の選別.シーン可視数 != 単一材質.可視個体の選別.シーン可視数 {
        return Err(format!(
            "材質を分けると可視個体の選別のシーン可視数が変わった: 2材質{}、1材質{}",
            二材質.可視個体の選別.シーン可視数, 単一材質.可視個体の選別.シーン可視数
        ));
    }
    Ok(())
}
