//! 2材質と1材質の計数を突き合わせる規則。触れるのは2つの計数報告だけであり、画素にも絵の書き出しにも触れない。
//! 材質を分けたときに増えてよい数(発行数・ジオメトリのセットの束縛)と、変わってはならない数(可視数・個体数・
//! 材質のセットの束縛・常駐画像枚数)をここが1箇所で決める。
//!
//! 資源表世代の材質件数と常駐画像枚数、およびセット別の束縛回数は`resource_table`が見る。

mod resource_table;

use crate::acceptance::{判定の名前, 判定の破れ};
use crate::report_parse::計数報告;

const シーンパスの可視数: 判定の名前 = 判定の名前::定数から生成する("材質を分けた2材質のシーンパスの可視数(1材質と一致するはずである)");
const シーンパスの個体数: 判定の名前 = 判定の名前::定数から生成する("材質を分けた2材質のシーンパスの個体数(1材質と一致するはずである)");
const 可視個体の選別のシーン可視数: 判定の名前 =
    判定の名前::定数から生成する("材質を分けた2材質の可視個体の選別のシーン可視数(1材質と一致するはずである)");

/// 発行数はプリミティブの数ぶん増え、可視ID数とシーン可視数は変わらない。
pub(super) fn 計数を検査する(二材質: &計数報告, 単一材質: &計数報告) -> Result<(), 判定の破れ> {
    crate::count_consistency::計数の整合を検査する("multi-material-draw(2材質)", 二材質)?;
    crate::count_consistency::計数の整合を検査する("multi-material-draw(1材質)", 単一材質)?;
    二材質のシーンパスの発行数の判定名(単一材質.シーン.発行数).一致を課す(二材質.シーン.発行数, 単一材質.シーン.発行数 + 1)?;
    可視の数が変わらないことを確かめる(二材質, 単一材質)?;
    resource_table::材質のセットの束縛が増えないことを確かめる(二材質, 単一材質)?;
    resource_table::正準フォールバックが材質で複製されないことを確かめる(二材質, 単一材質)?;
    for (名前, 計数) in [("2材質", 二材質), ("1材質", 単一材質)] {
        検証層の指摘の判定名(名前).零件であることを課す(計数.validation件数)?;
    }
    Ok(())
}

fn 可視の数が変わらないことを確かめる(二材質: &計数報告, 単一材質: &計数報告) -> Result<(), 判定の破れ> {
    シーンパスの可視数.一致を課す(二材質.シーン.可視数, 単一材質.シーン.可視数)?;
    シーンパスの個体数.一致を課す(二材質.シーン.個体数, 単一材質.シーン.個体数)?;
    可視個体の選別のシーン可視数.一致を課す(二材質.可視個体の選別.シーン可視数, 単一材質.可視個体の選別.シーン可視数)
}

fn 二材質のシーンパスの発行数の判定名(単一材質の発行数: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "2材質のシーンパスの発行数(1材質の{単一材質の発行数}回にプリミティブ1件ぶんを足した値になるはずである)"
    ))
}

fn 検証層の指摘の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}の実行で出た検証層の指摘"))
}
