//! 端末への複製。ログが一次の記録であり、端末はその複製先である。複製先が壊れても検証を止めないため、
//! この型は壊れたことを覚えて複製をやめ、以後は端末へ何も書かない。
//!
//! 書き込み先をトレイトで受けるのは、試験が途中から失敗する端末を差し込んで、壊れた後もログが揃うことを
//! 固定するためである。本番の実装は標準出力と標準エラーへ書く`本物の端末`だけである。

use std::io::Write;
use std::sync::Mutex;

/// 端末のどちらの流れへ書くか。
pub enum 端末の流れの種別 {
    標準出力,
    標準エラー,
}

/// 端末へ1つの塊を書いて掃き出すまでを1回とする書き込み先。
pub trait 端末の書き込み先: Send + Sync {
    fn 掃き出しながら書く(&self, 種別: &端末の流れの種別, 塊: &[u8]) -> std::io::Result<()>;
}

pub struct 本物の端末;

impl 端末の書き込み先 for 本物の端末 {
    fn 掃き出しながら書く(&self, 種別: &端末の流れの種別, 塊: &[u8]) -> std::io::Result<()> {
        match 種別 {
            端末の流れの種別::標準出力 => 書いて掃き出す(&mut std::io::stdout().lock(), 塊),
            端末の流れの種別::標準エラー => 書いて掃き出す(&mut std::io::stderr().lock(), 塊),
        }
    }
}

fn 書いて掃き出す(書き先: &mut dyn Write, 塊: &[u8]) -> std::io::Result<()> {
    書き先.write_all(塊)?;
    書き先.flush()
}

/// 複製を続けているか、破れて止めたか。止めた後は同じ破れを二度と報告せず、端末へも書かない。
enum 端末への複製の状態 {
    複製している,
    破れて止めた { 最初の破れの説明: String },
}

pub struct 端末への複製係 {
    書き込み先: Box<dyn 端末の書き込み先>,
    状態: Mutex<端末への複製の状態>,
}

impl 端末への複製係 {
    pub fn 本物の端末へ複製する() -> Self {
        Self::書き込み先を指定して作る(Box::new(本物の端末))
    }

    pub fn 書き込み先を指定して作る(書き込み先: Box<dyn 端末の書き込み先>) -> Self {
        Self {
            書き込み先,
            状態: Mutex::new(端末への複製の状態::複製している),
        }
    }

    /// 複製を試み、この呼び出しで初めて破れたときだけその説明を返す。呼び出し側はそれをログへ1行として書く。
    /// 既に止めた後は端末へ書かずに`None`を返すため、壊れた端末へ塊ごとに書き続けることはない。
    pub fn 複製して初めての破れだけを返す(&self, 種別: &端末の流れの種別, 塊: &[u8]) -> Option<String> {
        let mut 状態 = self.状態を借りる();
        if matches!(*状態, 端末への複製の状態::破れて止めた { .. }) {
            return None;
        }
        let 説明 = self.書き込み先.掃き出しながら書く(種別, 塊).err()?.to_string();
        *状態 = 端末への複製の状態::破れて止めた {
            最初の破れの説明: 説明.clone(),
        };
        Some(説明)
    }

    /// 端末が破れたまま終わったかを、最初の破れの説明で答える。
    pub fn 破れの説明(&self) -> Option<String> {
        match &*self.状態を借りる() {
            端末への複製の状態::複製している => None,
            端末への複製の状態::破れて止めた { 最初の破れの説明 } => Some(最初の破れの説明.clone()),
        }
    }

    /// 錠が毒に侵されるのは持ち主が中で慌てて落ちたときだけであり、この型は中で落ちない。
    /// それでも中身を取り出して進むのは、端末の事故を理由にログの記録を止めないためである。
    fn 状態を借りる(&self) -> std::sync::MutexGuard<'_, 端末への複製の状態> {
        self.状態.lock().unwrap_or_else(|毒| 毒.into_inner())
    }
}
