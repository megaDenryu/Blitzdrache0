//! 端末が壊れた後もログが一次の記録であり続けることの検査。参照: PR #83のレビューの必須
//!
//! 固定するのは3つである。端末が壊れた後の流れもログへ残ること。端末の破れ自体がログで分かること。
//! 子プロセスの管を読む輪が最後まで読んで返ること。
//! 管を読む輪へ試験が直接、長い流れを与えるのは、`子プロセスの出力を流す`が実際に読む輪がこの関数だからである。

use std::sync::Arc;
use std::sync::atomic::{AtomicUsize, Ordering};

use super::terminal_copy::{端末の書き込み先, 端末の流れの種別, 端末への複製係};
use super::{検証列の破れ, 端末とログの両方へ流す出力係};

mod test_doubles;

use test_doubles::{必ず失敗するログ, 数える読み元, 覚えているログ, 途中から壊れる端末};

/// 流す塊の本数。1本目で端末を壊しても残りが全部ログへ入ることを見るため、2本より多くする。
const 流す塊の本数: usize = 5;

fn 出力係を組み立てる(
    ログの中身: &Arc<std::sync::Mutex<Vec<u8>>>, 端末の成功回数: usize
) -> 端末とログの両方へ流す出力係 {
    let 端末: Box<dyn 端末の書き込み先> = Box::new(途中から壊れる端末::残りの成功回数を決めて作る(端末の成功回数));
    端末とログの両方へ流す出力係::書き込み先を指定して作る(
        Box::new(覚えているログ::同じ中身を指して作る(ログの中身)),
        端末への複製係::書き込み先を指定して作る(端末),
    )
}

fn 管を流した結末(
    出力係: &端末とログの両方へ流す出力係, 読まれた塊数: &Arc<AtomicUsize>
) -> Result<(), 検証列の破れ> {
    let 読み元 = 数える読み元::本数と数え札を決めて作る(流す塊の本数, 読まれた塊数);
    出力係.管を最後まで流す(読み元, &端末の流れの種別::標準出力)
}

#[test]
fn 端末が壊れた後の流れもログへ残り管は最後まで読まれる() {
    let ログの中身 = Arc::new(std::sync::Mutex::new(Vec::new()));
    let 読まれた塊数 = Arc::new(AtomicUsize::new(0));
    let 出力係 = 出力係を組み立てる(&ログの中身, 1);
    let 結末 = 管を流した結末(&出力係, &読まれた塊数);
    assert!(結末.is_ok(), "端末の破れで管を流す仕事まで失敗している");
    assert_eq!(読まれた塊数.load(Ordering::Relaxed), 流す塊の本数, "管を最後まで読んでいない");
    let 本文 = String::from_utf8(ログの中身.lock().unwrap().clone()).unwrap();
    for 番号 in 0..流す塊の本数 {
        assert!(本文.contains(&format!("塊{番号}\n")), "端末が壊れた後の流れがログから欠けている: {本文}");
    }
    assert!(
        本文.contains("端末への複製が破れたため複製を止めた"),
        "端末の破れがログで分からない: {本文}"
    );
    assert!(出力係.端末への複製の破れ().is_some(), "端末の破れを最後まで覚えていない");
}

#[test]
fn ログへ書けなくなっても管は最後まで読まれて破れが返る() {
    let 読まれた塊数 = Arc::new(AtomicUsize::new(0));
    let 出力係 = 端末とログの両方へ流す出力係::書き込み先を指定して作る(
        Box::new(必ず失敗するログ),
        端末への複製係::書き込み先を指定して作る(Box::new(途中から壊れる端末::残りの成功回数を決めて作る(
            流す塊の本数,
        ))),
    );
    let 結末 = 管を流した結末(&出力係, &読まれた塊数);
    assert!(結末.is_err(), "ログへ書けないのに破れを返していない");
    assert_eq!(
        読まれた塊数.load(Ordering::Relaxed),
        流す塊の本数,
        "ログが壊れた後に管の読み取りを止めている"
    );
    assert!(出力係.端末への複製の破れ().is_none(), "端末は壊れていないのに破れたことになっている");
}

/// 読み元が終わりを告げるまで読み続けることを、読み元の側からも見る。
#[test]
fn 端末が最初から壊れていても管は最後まで読まれる() {
    let ログの中身 = Arc::new(std::sync::Mutex::new(Vec::new()));
    let 読まれた塊数 = Arc::new(AtomicUsize::new(0));
    let 出力係 = 出力係を組み立てる(&ログの中身, 0);
    assert!(管を流した結末(&出力係, &読まれた塊数).is_ok(), "端末の破れで管を流す仕事まで失敗している");
    assert_eq!(読まれた塊数.load(Ordering::Relaxed), 流す塊の本数, "管を最後まで読んでいない");
    assert!(
        String::from_utf8(ログの中身.lock().unwrap().clone()).unwrap().contains("塊4\n"),
        "端末が最初から壊れているとログへ何も残らない"
    );
}
