//! 実行モード: この入口が消すのか、消せるものの一覧だけを出すのかの2通り。
//!
//! 裸の真偽値で持ち回らないのは、入口から報告までの工程を貫通し、どちらの真がどちらを意味するかが
//! 呼び出し側の記憶に頼ることになるためである。旗の綴りの正本もここに置き、コマンド一覧の引数の宣言と
//! 引数の読み取りが同じ綴りを見る。

/// 消さずに一覧だけを出す旗の綴り。コマンド一覧の引数の宣言と、この入口の引数の読み取りが共に見る。
pub(crate) const 消さずに一覧だけ出す旗: &str = "--dry-run";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 実行モード {
    消さずに一覧だけ出す,
    消す,
}

impl 実行モード {
    /// 引数の並びから読む。知らない語を1つでも受け取ったら、その語を返して呼び出し側に落とさせる。
    pub(super) fn 引数一覧から読む(引数一覧: &[String]) -> Result<Self, &str> {
        let mut モード = Self::消す;
        for 語 in 引数一覧 {
            if 語 == 消さずに一覧だけ出す旗 {
                モード = Self::消さずに一覧だけ出す;
                continue;
            }
            return Err(語);
        }
        Ok(モード)
    }

    /// 合計の容量を告げる1行の見出し。消した後と、消す前の見積もりとで言うことが違う。
    pub(super) fn 合計の見出し(self) -> &'static str {
        match self {
            Self::消さずに一覧だけ出す => "消せば解放する容量の合計は",
            Self::消す => "解放した容量の合計は",
        }
    }
}
