//! 掃除の候補を集める工程。受け取るのは無し、返すのは消す候補の並びである。
//!
//! **ここが「消してよい」の判断を持つ唯一の場所である。** 挙げるのはどれも、失うものが
//! 「次の1回のビルドが差分でなく全部になること」だけの置き場に限る。消えたことを知らない側は
//! 再ビルドで待つだけであり、成果物を失わない。
//!
//! いま自分が使っている出力先だけは、実在しても消さずに残す枝で返す。掃除の最中に自分の実行ファイルの
//! 置き場を消すためである。黙って一覧から落とさないのは、読み手が「無かった」と読み違えるためである。

use std::path::{Path, PathBuf};

use super::error::掃除の破れ;
use super::subject::掃除の対象;
use crate::verify::検証の出力ルート;

/// 作業ツリーごとの出力先を見分ける印。木の名前に続けてこの印を書いた兄弟が、その作業ツリー専用の出力先である。
const 作業ツリーごとの出力先の印: char = '-';
/// 作業ツリーごとの出力先が並ぶ親。xtaskはリポジトリのルートで走るため、今いる場所がそれである。
const 出力先が並ぶ親: &str = ".";

pub(super) enum 掃除の候補 {
    消す(掃除の対象),
    いま使っているため残す(掃除の対象),
}

pub(super) fn 掃除の候補を集める() -> Result<Vec<掃除の候補>, 掃除の破れ> {
    let ルート = 検証の出力ルート::既定();
    let いま使っている出力先 = 検証の出力ルート::いま使っている木();
    let mut 候補一覧 = vec![
        掃除の候補::消す(掃除の対象::生成する(
            "差分ビルドの中間データ".to_string(),
            ルート.差分ビルドの中間データの置き場(),
        )),
        掃除の候補::消す(掃除の対象::生成する(
            "codexレビュー用のビルドの出力先".to_string(),
            ルート.codexレビューのビルドの出力先(),
        )),
    ];
    for パス in 作業ツリーごとの出力先一覧(ルート.木の名前())? {
        let 対象 = 掃除の対象::生成する(format!("作業ツリーごとのビルドの出力先({})", パス.display()), パス);
        候補一覧.push(if 同じ場所か(対象.パス(), &いま使っている出力先) {
            掃除の候補::いま使っているため残す(対象)
        } else {
            掃除の候補::消す(対象)
        });
    }
    Ok(候補一覧)
}

/// 木の名前に印を続けた名前を持つ、リポジトリのルートの直下のディレクトリ。
fn 作業ツリーごとの出力先一覧(木の名前: &str) -> Result<Vec<PathBuf>, 掃除の破れ> {
    let 親 = Path::new(出力先が並ぶ親);
    let 読めなかった = |誤り| 掃除の破れ::ディレクトリを読めなかった {
        ディレクトリ: 親.to_path_buf(),
        誤り,
    };
    let 接頭辞 = format!("{木の名前}{作業ツリーごとの出力先の印}");
    let mut 一覧 = Vec::new();
    for エントリ結果 in std::fs::read_dir(親).map_err(読めなかった)? {
        let エントリ = エントリ結果.map_err(読めなかった)?;
        if !エントリ.file_type().map_err(読めなかった)?.is_dir() {
            continue;
        }
        if エントリ.file_name().to_string_lossy().starts_with(&接頭辞) {
            一覧.push(エントリ.path());
        }
    }
    一覧.sort();
    Ok(一覧)
}

/// 2つのパスが同じ場所を指すか。綴りが違っても同じ場所を指しうるため、実体の解決を通してから比べる。
/// 解決できないパスは実在しないため、同じ場所ではない。
fn 同じ場所か(片方: &Path, もう片方: &Path) -> bool {
    match (片方.canonicalize(), もう片方.canonicalize()) {
        (Ok(左), Ok(右)) => 左 == 右,
        (Err(_), _) | (_, Err(_)) => false,
    }
}
