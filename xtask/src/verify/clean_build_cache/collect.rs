//! 掃除の候補を集める工程。受け取るのはいまのビルドが使っている出力の木、返すのは候補の並びである。
//!
//! **ここが「消してよい」の判断を持つ唯一の場所である。** 挙げるのはどれも、失うものが
//! 「次の1回のビルドが差分でなく全部になること」だけの置き場に限る。消えたことを知らない側は
//! 再ビルドで待つだけであり、成果物を失わない。
//!
//! いま自分が使っている出力先を残す判断は、この工程が種類ごとに書かず、候補を作る口である
//! `掃除の候補::対象から生成する`が全部の候補へ同じく当てる。

use std::path::{Path, PathBuf};

use super::candidate::掃除の候補;
use super::error::掃除の破れ;
use super::role::掃除の対象の役割;
use super::subject::掃除の対象;
use crate::verify::検証の出力ルート;

/// 作業ツリーごとの出力先が並ぶ親。xtaskはリポジトリのルートで走るため、今いる場所がそれである。
const 出力先が並ぶ親: &str = ".";

pub(super) fn 掃除の候補を集める(いま使っている木: &Path) -> Result<Vec<掃除の候補>, 掃除の破れ> {
    let ルート = 検証の出力ルート::既定();
    let 置き場一覧 = [
        (掃除の対象の役割::差分ビルドの中間データ, ルート.差分ビルドの中間データの置き場()),
        (掃除の対象の役割::Codexレビューのビルドの出力先, ルート.codexレビューのビルドの出力先()),
    ];
    let mut 候補一覧: Vec<掃除の候補> = 置き場一覧
        .into_iter()
        .map(|(役割, パス)| 掃除の候補::対象から生成する(掃除の対象::生成する(役割, パス), いま使っている木))
        .collect();
    for パス in 作業ツリーごとの出力先一覧(&ルート.作業ツリーごとの出力先の接頭辞())? {
        let 対象 = 掃除の対象::生成する(掃除の対象の役割::作業ツリーごとのビルドの出力先, パス);
        候補一覧.push(掃除の候補::対象から生成する(対象, いま使っている木));
    }
    Ok(候補一覧)
}

/// 接頭辞で始まる名前を持つ、リポジトリのルートの直下のディレクトリ。
fn 作業ツリーごとの出力先一覧(接頭辞: &str) -> Result<Vec<PathBuf>, 掃除の破れ> {
    let 親 = Path::new(出力先が並ぶ親);
    let 読めなかった = |誤り| 掃除の破れ::ディレクトリを読めなかった {
        ディレクトリ: 親.to_path_buf(),
        誤り,
    };
    let mut 一覧 = Vec::new();
    for エントリ結果 in std::fs::read_dir(親).map_err(読めなかった)? {
        let エントリ = エントリ結果.map_err(読めなかった)?;
        if !エントリ.file_type().map_err(読めなかった)?.is_dir() {
            continue;
        }
        if エントリ.file_name().to_string_lossy().starts_with(接頭辞) {
            一覧.push(エントリ.path());
        }
    }
    一覧.sort();
    Ok(一覧)
}
