//! 掃除の候補: 集めた対象1つが、消してよいのか、いま使っているため残すのかの2通り。
//!
//! いま使っている出力先を一覧から黙って落とさずこの枝で持つのは、読み手が「無かった」と読み違えるためである。
//! 報告と処理をこの型のメソッドにするのは、何を言い何を消すかを決めるのがこの区別そのものだからである。
//!
//! **候補を作る口を`対象から生成する`の1つだけにしてあるのは、いま使っている出力の木を守る判断を候補の種類ごとに
//! 書かせないためである。** 種類ごとに書く形は、`CARGO_TARGET_DIR`へ据えられうる置き場を新しく候補へ足した人が
//! 守りを書き忘れることを止められず、実際に固定の候補の側で守りが抜けていた。

use std::path::Path;

use super::error::掃除の破れ;
use super::mode::実行モード;
use super::occupied_size::占める容量;
use super::subject::掃除の対象;

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests;

pub(super) enum 掃除の候補 {
    消す(掃除の対象),
    いま使っているため残す(掃除の対象),
}

impl 掃除の候補 {
    /// 対象1つを、いまのビルドが使っている出力の木と突き合わせて振り分ける。同じ場所なら残す枝にする。
    /// 木そのものと同じ場所である候補だけを守り、木の一部分である候補(差分ビルドの中間データ)は消す枝のままにする。
    pub(super) fn 対象から生成する(対象: 掃除の対象, いま使っている木: &Path) -> Self {
        if 同じ場所か(対象.パス(), いま使っている木) {
            return Self::いま使っているため残す(対象);
        }
        Self::消す(対象)
    }

    /// この候補の1行を報告し、消す枝で実在するものだけを消す。返すのはこの1件が解放する容量である。
    pub(super) fn 報告して処理する(&self, モード: 実行モード) -> Result<占める容量, 掃除の破れ> {
        let (Self::消す(対象) | Self::いま使っているため残す(対象)) = self;
        let 置き場 = 対象.パス().display();
        if !対象.実在するか() {
            println!("[xtask] 無い: {} ({置き場})", 対象.役割());
            return Ok(占める容量::無し());
        }
        let 容量 = 対象.容量を測る()?;
        match (self, モード) {
            (Self::いま使っているため残す(_), _) => {
                println!("[xtask] 残す: {} ({置き場}, {容量})。いまのビルドがこの出力先を使っている", 対象.役割());
                Ok(占める容量::無し())
            }
            (Self::消す(_), 実行モード::消さずに一覧だけ出す) => {
                println!("[xtask] 消せる: {} ({置き場}, {容量})", 対象.役割());
                Ok(容量)
            }
            (Self::消す(_), 実行モード::消す) => {
                対象.消す()?;
                println!("[xtask] 消した: {} ({置き場}, {容量})", 対象.役割());
                Ok(容量)
            }
        }
    }
}

/// 2つのパスが同じ場所を指すか。綴りが違っても同じ場所を指しうるため、実体の解決を通してから比べる。
/// 解決できないパスは実在しないため、同じ場所ではない。
fn 同じ場所か(片方: &Path, もう片方: &Path) -> bool {
    match (片方.canonicalize(), もう片方.canonicalize()) {
        (Ok(左), Ok(右)) => 左 == 右,
        (Err(_), _) | (_, Err(_)) => false,
    }
}
