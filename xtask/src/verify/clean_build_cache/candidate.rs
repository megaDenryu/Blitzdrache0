//! 掃除の候補: 集めた対象1つが、消してよいのか、いま使っているため残すのかの2通り。
//!
//! いま使っている出力先を一覧から黙って落とさずこの枝で持つのは、読み手が「無かった」と読み違えるためである。
//! 報告と処理をこの型のメソッドにするのは、何を言い何を消すかを決めるのがこの区別そのものだからである。

use super::error::掃除の破れ;
use super::mode::実行モード;
use super::occupied_size::占める容量;
use super::subject::掃除の対象;

pub(super) enum 掃除の候補 {
    消す(掃除の対象),
    いま使っているため残す(掃除の対象),
}

impl 掃除の候補 {
    /// この候補の1行を報告し、消す枝で実在するものだけを消す。返すのはこの1件が解放する容量である。
    pub(super) fn 報告して処理する(&self, モード: 実行モード) -> Result<占める容量, 掃除の破れ> {
        let (Self::消す(対象) | Self::いま使っているため残す(対象)) = self;
        let 置き場 = 対象.パス().display();
        if !対象.実在するか() {
            println!("[xtask] 無い: {} ({置き場})", 対象.役割());
            return Ok(占める容量::無し());
        }
        let 容量 = 対象.容量を測る()?;
        match (self, モード) {
            (Self::いま使っているため残す(_), _) => {
                println!("[xtask] 残す: {} ({置き場}, {容量})。いまのビルドがこの出力先を使っている", 対象.役割());
                Ok(占める容量::無し())
            }
            (Self::消す(_), 実行モード::消さずに一覧だけ出す) => {
                println!("[xtask] 消せる: {} ({置き場}, {容量})", 対象.役割());
                Ok(容量)
            }
            (Self::消す(_), 実行モード::消す) => {
                対象.消す()?;
                println!("[xtask] 消した: {} ({置き場}, {容量})", 対象.役割());
                Ok(容量)
            }
        }
    }
}
