//! 掃除の対象の役割: 消してよいビルドの中間データの置き場が、どういう役目で在るかの3通り。
//!
//! 呼び名を`String`で持ち回らないのは、種類が閉じており、呼び名の組み立てが場所ごとに違う形になるためである。
//! 実際、作業ツリーごとの出力先だけが呼び名へパスを埋め込み、報告の行にパスが二重に出ていた。
//! 判別共用体にすると、呼び名の綴りが枝ごとに1つへ定まり、報告の側はパスを1度だけ書く。

use std::fmt;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 掃除の対象の役割 {
    差分ビルドの中間データ,
    Codexレビューのビルドの出力先,
    作業ツリーごとのビルドの出力先,
}

impl fmt::Display for 掃除の対象の役割 {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        let 呼び名 = match self {
            Self::差分ビルドの中間データ => "差分ビルドの中間データ",
            Self::Codexレビューのビルドの出力先 => "codexレビュー用のビルドの出力先",
            Self::作業ツリーごとのビルドの出力先 => "作業ツリーごとのビルドの出力先",
        };
        書き手.write_str(呼び名)
    }
}
