//! 検証の出力の置き場名: 検証の出力が載る木の直下に掘る置き場1つの名前を表す値オブジェクト。
//!
//! 入口がパスの文字列ごと持たずに名前だけを持つのは、木の名前と置き場の名前を1つの文字列へ潰すと、
//! 木を移したときに触り漏らした入口だけが古い場所へ書き続けるためである。名前だけを持てば、
//! 木の名前を知っているのは`検証の出力ルート`だけになる。
//!
//! 検証を構築時に行うのは、文字列が不正でもパスを組むところまでは成功し、書き出す段になって初めて
//! 「作れない」で失敗するためである。失敗を実行の奥まで遅らせない。

use super::spelling;

#[repr(transparent)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 検証の出力の置き場名(&'static str);

impl 検証の出力の置き場名 {
    /// 名前の表が`const`のまま書けるように`const fn`にする。破れは実行時の失敗でなくコンパイルの失敗として出る。
    ///
    /// 注意: 破れたときに`panic!`へ落ちるのは、この関数がコンパイル時の定数にしか適用されず、
    /// 破れが到達したらプログラムのバグだからである。破れの文字列は定数の定義位置がそのまま指す。
    pub(crate) const fn 生成する(文字列: &'static str) -> Self {
        if spelling::空か(文字列) {
            panic!("検証の出力の置き場名が空である");
        }
        if spelling::区切りを含むか(文字列) {
            panic!("検証の出力の置き場名が区切りを含み、木の直下の1つの置き場を指していない");
        }
        if spelling::場所を指す文字列か(文字列) {
            panic!("検証の出力の置き場名が場所を指す文字列であり、置き場を1つも指していない");
        }
        if spelling::コロンを含むか(文字列) {
            panic!("検証の出力の置き場名がコロンを含み、Windowsの連結で基準のディレクトリを置き換える");
        }
        Self(文字列)
    }

    /// 人へ見せる文字列と、名前を文字列でしか受け取れない口へ渡す文字列。パスを組む口ではない。
    /// パスは`検証の出力ルート`が組む。
    pub(crate) const fn 文字列を見せる(self) -> &'static str {
        self.0
    }
}
