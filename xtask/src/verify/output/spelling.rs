//! 置き場の名前の綴りの検査。受け取るのは綴り、返すのはその条件に当たるかどうかである。
//! 拒む理由は条件ごとに違うため、条件ごとの関数に分けて、理由は呼び出す側の`生成する`に書く。
//!
//! `const fn`にするのは、置き場の名前がすべてコンパイル時の定数であり、破れをコンパイルの失敗として
//! 出すためである。実行時まで持ち越すと、不正な綴りが「そのディレクトリを作れない」という遠い場所の失敗になる。
//!
//! バイト単位で走査するのは、UTF-8の多バイト文字がASCIIのバイトを1つも含まないため、
//! 斜線・逆斜線・コロン・点を探すのにバイトの突き合わせで足りるからである。

const 斜線: u8 = b'/';
const 逆斜線: u8 = b'\\';
const コロン: u8 = b':';
const 点: u8 = b'.';

pub(super) const fn 空か(綴り: &str) -> bool {
    綴り.is_empty()
}

pub(super) const fn 区切りを含むか(綴り: &str) -> bool {
    指定のバイトを含むか(綴り, 斜線) || 指定のバイトを含むか(綴り, 逆斜線)
}

pub(super) const fn コロンを含むか(綴り: &str) -> bool {
    指定のバイトを含むか(綴り, コロン)
}

/// 点だけ、または点が2つ続く所を含むか。どちらも親や今の場所を指し、木の下の1つの置き場を指さない。
pub(super) const fn 場所を指す綴りか(綴り: &str) -> bool {
    let バイト列 = 綴り.as_bytes();
    if バイト列.len() == 1 && バイト列[0] == 点 {
        return true;
    }
    let mut 位置 = 1;
    while 位置 < バイト列.len() {
        if バイト列[位置] == 点 && バイト列[位置 - 1] == 点 {
            return true;
        }
        位置 += 1;
    }
    false
}

const fn 指定のバイトを含むか(綴り: &str, 印: u8) -> bool {
    let バイト列 = 綴り.as_bytes();
    let mut 位置 = 0;
    while 位置 < バイト列.len() {
        if バイト列[位置] == 印 {
            return true;
        }
        位置 += 1;
    }
    false
}
