//! 検証のログを置く場所。受け取るのはログのファイル名、返すのはそのファイルの絶対パスである。
//! 出力の木の綴り(`CARGO_TARGET_DIR`があればその値、無ければ`target`)と`verify-logs`の綴りをこの型へ閉じる。
//!
//! 注意: PR #79が入れる`検証の出力ルート`がマージされたら、この型の`出力の木`は
//! `検証の出力ルート::いま使っている木()`へ寄せる。いまの`main`にその型が無いため、ここで自前の小さな型として持つ。

use std::path::{Path, PathBuf};

use super::log_error::検証列の破れ;

/// 出力の木の中でログを集める区画の名前。読む側がこの1語でログの置き場を探す。
const ログを集める区画の名前: &str = "verify-logs";

/// 出力の木の場所を指す環境変数の名前。cargoがこの値を見て成果物の置き場を決める。
const 出力の木を指す環境変数: &str = "CARGO_TARGET_DIR";

/// 環境変数が無いときの出力の木。cargoの既定と同じ綴りである。
const 既定の出力の木: &str = "target";

pub struct 検証のログの置き場 {
    出力の木: PathBuf,
}

impl 検証のログの置き場 {
    pub fn いま使っている木から決める() -> Self {
        let 出力の木 = std::env::var_os(出力の木を指す環境変数).map_or_else(|| PathBuf::from(既定の出力の木), PathBuf::from);
        Self { 出力の木 }
    }

    /// 置き場を作ってから、その中の1つのログのファイルの絶対パスを返す。相対の出力の木を作業ディレクトリで
    /// 絶対にするのは、端末へ出したパスをそのまま別の場所から開けるようにするためである。
    pub fn ログのファイルの絶対パスを用意する(&self, ファイル名: &str) -> Result<PathBuf, 検証列の破れ> {
        let ディレクトリ = self.出力の木.join(ログを集める区画の名前);
        std::fs::create_dir_all(&ディレクトリ).map_err(|誤り| 検証列の破れ::ログの置き場を作れなかった {
            ディレクトリ: ディレクトリ.clone(),
            誤り,
        })?;
        let 作業ディレクトリ = std::env::current_dir().map_err(検証列の破れ::作業ディレクトリを読めなかった)?;
        Ok(斜線へ揃える(&作業ディレクトリ.join(ディレクトリ).join(ファイル名)))
    }
}

/// パスの区切りを斜線へ揃える。`CARGO_TARGET_DIR`が斜線で、`join`が円記号を足すため、揃えないと
/// 端末へ出す1本の綴りに2種類の区切りが混ざる。Windowsのファイルの口も斜線を受け取るため、内部でもこの形で持つ。
fn 斜線へ揃える(パス: &Path) -> PathBuf {
    PathBuf::from(パス.to_string_lossy().replace('\\', "/"))
}
