//! 検証のログを置く場所。受け取るのはログのファイル名、返すのはそのファイルの絶対パスである。
//! いまのビルドが使っている出力の木の下の`verify-logs`を指し、その置き場の名前をこの型へ閉じる。
//!
//! 木の名前を綴らないのは、綴ってよいのが`検証の出力ルート`だけだからである。置き場の名前を裸の文字列でなく
//! `検証の出力の置き場名`で持つのは、区切りやコロンを含む綴りをコンパイルの時点で弾くためである。

use std::path::{Path, PathBuf};

use super::log_error::検証列の破れ;
use super::log_file_name::検証のログのファイル名;
use super::{検証の出力の置き場名, 検証の出力ルート};

/// 出力の木の中でログを集める置き場の名前。読む側がこの1語でログの置き場を探す。
const ログを集める置き場の名前: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("verify-logs");

/// 同じブランチ・同じ先端・同じ秒に何本まで場所を押さえるか。ここを使い切るのは1秒に99回起動したときであり、
/// そこまで来たら人の操作ではないため、黙って上書きせず破れとして告げる。
const 同じ秒に許す本数: u32 = 99;

pub struct 検証のログの置き場 {
    出力の木: PathBuf,
}

impl 検証のログの置き場 {
    pub fn いま使っている木から決める() -> Self {
        Self {
            出力の木: 検証の出力ルート::いま使っている木(),
        }
    }

    /// 置き場を作ってから、その中の1つのログのファイルの絶対パスを返す。相対の出力の木を作業ディレクトリで
    /// 絶対にするのは、端末へ出したパスをそのまま別の場所から開けるようにするためである。
    pub fn ログのファイルの絶対パスを用意する(
        &self, ファイル名: &検証のログのファイル名
    ) -> Result<PathBuf, 検証列の破れ> {
        let ディレクトリ = self.出力の木.join(ログを集める置き場の名前.綴りを見せる());
        std::fs::create_dir_all(&ディレクトリ).map_err(|誤り| 検証列の破れ::ログの置き場を作れなかった {
            ディレクトリ: ディレクトリ.clone(),
            誤り,
        })?;
        let 作業ディレクトリ = std::env::current_dir().map_err(検証列の破れ::作業ディレクトリを読めなかった)?;
        let 絶対のディレクトリ = 作業ディレクトリ.join(ディレクトリ);
        Ok(斜線へ揃える(&空いている名前で場所を押さえる(
            &絶対のディレクトリ,
            ファイル名,
        )?))
    }
}

/// 空いている名前を選び、その場で空のファイルを作って場所を押さえる。選ぶことと作ることを1つの操作にするのは、
/// 選んでから開くまでの間に同じ秒に始まった別の実行が同じ名前を取るのを防ぐためである。
/// 前の実行が書いたログを黙って切り詰めないことがこの工程の目的である。参照: PR #83のレビュー
fn 空いている名前で場所を押さえる(
    ディレクトリ: &Path, ファイル名: &検証のログのファイル名
) -> Result<PathBuf, 検証列の破れ> {
    for 何本目 in 1..=同じ秒に許す本数 {
        let 候補 = ディレクトリ.join(ファイル名.何本目かで区別する綴り(何本目));
        match std::fs::OpenOptions::new().write(true).create_new(true).open(&候補) {
            Ok(_) => return Ok(候補),
            Err(誤り) if 誤り.kind() == std::io::ErrorKind::AlreadyExists => continue,
            Err(誤り) => return Err(検証列の破れ::ログのファイルを開けなかった { パス: 候補, 誤り }),
        }
    }
    Err(検証列の破れ::同じ秒のログの名前を使い切った {
        ディレクトリ: ディレクトリ.to_path_buf(),
        上限の本数: 同じ秒に許す本数,
    })
}

/// パスの区切りを斜線へ揃える。`CARGO_TARGET_DIR`が斜線で、`join`が円記号を足すため、揃えないと
/// 端末へ出す1本の綴りに2種類の区切りが混ざる。Windowsのファイルの口も斜線を受け取るため、内部でもこの形で持つ。
fn 斜線へ揃える(パス: &Path) -> PathBuf {
    PathBuf::from(パス.to_string_lossy().replace('\\', "/"))
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;
    use std::sync::atomic::{AtomicU32, Ordering};

    /// 同じ試験の実行の中で置き場の名前がぶつからないようにする番号。
    static 使い捨ての置き場の通し番号: AtomicU32 = AtomicU32::new(0);

    fn 使い捨てのディレクトリを作る() -> PathBuf {
        let 番号 = 使い捨ての置き場の通し番号.fetch_add(1, Ordering::Relaxed);
        let ディレクトリ = std::env::temp_dir().join(format!("blitzdrache0-検証のログの置き場の検査-{}-{番号}", std::process::id()));
        std::fs::create_dir_all(&ディレクトリ).unwrap();
        ディレクトリ
    }

    #[test]
    fn 同じ基礎の名前を二回押さえても一本目の中身が消えない() {
        let ディレクトリ = 使い捨てのディレクトリを作る();
        let ファイル名 =
            検証のログのファイル名::試験のために拡張子を除く綴りから作る("ブランチ_abc1234_19700101-000000");
        let 一本目 = 空いている名前で場所を押さえる(&ディレクトリ, &ファイル名).unwrap();
        std::fs::write(&一本目, "前の実行が残した証拠").unwrap();
        let 二本目 = 空いている名前で場所を押さえる(&ディレクトリ, &ファイル名).unwrap();
        let 一本目の中身 = std::fs::read_to_string(&一本目).unwrap();
        std::fs::remove_dir_all(&ディレクトリ).unwrap();
        assert_ne!(一本目, 二本目, "同じ秒の2本目が1本目と同じ名前を取っている");
        assert_eq!(一本目の中身, "前の実行が残した証拠", "2本目の押さえが1本目の証拠を消している");
    }
}
