//! 検証列を最後まで走らせられなかったことを表す型付きエラー。破れうる前提を選択肢で数え上げ、どれが破れたかを型で言う。
//!
//! 各段が見つけた規約破りやコンパイルエラーはこの型に入らない。あれは段の終了コードとログの中身で表す。
//! こちらは「ログのファイルを用意できなかった」「段の子プロセスを起動できなかった」という、
//! 判定に到達できなかった側である。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きの列挙と`Display`で書く。様式は`conform/error.rs`に倣う。

use std::path::PathBuf;

#[derive(Debug)]
pub enum 検証列の破れ {
    ブランチまたは先端を読めなかった {
        問い合わせ: &'static str,
        誤り: std::io::Error,
    },
    ブランチまたは先端の問い合わせが失敗した {
        問い合わせ: &'static str,
        標準エラー: String,
    },
    時計が1970年より前を指している,
    作業ディレクトリを読めなかった(std::io::Error),
    ログの置き場を作れなかった {
        ディレクトリ: PathBuf,
        誤り: std::io::Error,
    },
    ログのファイルを開けなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    同じ秒のログの名前を使い切った {
        ディレクトリ: PathBuf,
        上限の本数: u32,
    },
    端末かログへ書けなかった(std::io::Error),
    自分の実行ファイルの場所を読めなかった(std::io::Error),
    段の子プロセスを起動できなかった(std::io::Error),
    段の子プロセスの出力の管が開かなかった,
    段の出力を読めなかった(std::io::Error),
    段の終了を待てなかった(std::io::Error),
    段の出力を流すスレッドが落ちた,
}

impl std::error::Error for 検証列の破れ {}

impl std::fmt::Display for 検証列の破れ {
    fn fmt(&self, 書き先: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::ブランチまたは先端を読めなかった { 問い合わせ, 誤り } => {
                write!(書き先, "gitへの問い合わせ({問い合わせ})を起動できなかった: {誤り}")
            }
            Self::ブランチまたは先端の問い合わせが失敗した {
                問い合わせ, 標準エラー
            } => {
                write!(書き先, "gitへの問い合わせ({問い合わせ})が失敗した: {標準エラー}")
            }
            Self::時計が1970年より前を指している => write!(書き先, "この計算機の時計が1970年1月1日より前を指している"),
            Self::作業ディレクトリを読めなかった(誤り) => write!(書き先, "作業ディレクトリを読めなかった: {誤り}"),
            Self::ログの置き場を作れなかった { ディレクトリ, 誤り } => {
                write!(書き先, "ログの置き場({})を作れなかった: {誤り}", ディレクトリ.display())
            }
            Self::ログのファイルを開けなかった { パス, 誤り } => {
                write!(書き先, "ログのファイル({})を開けなかった: {誤り}", パス.display())
            }
            Self::同じ秒のログの名前を使い切った {
                ディレクトリ, 上限の本数
            } => {
                write!(
                    書き先,
                    "同じ秒に始まったログの名前を{上限の本数}本まで試したがすべて埋まっていた({})",
                    ディレクトリ.display()
                )
            }
            Self::端末かログへ書けなかった(誤り) => write!(書き先, "端末かログへ書けなかった: {誤り}"),
            Self::自分の実行ファイルの場所を読めなかった(誤り) => {
                write!(書き先, "自分の実行ファイルの場所を読めなかった: {誤り}")
            }
            Self::段の子プロセスを起動できなかった(誤り) => write!(書き先, "段の子プロセスを起動できなかった: {誤り}"),
            Self::段の子プロセスの出力の管が開かなかった => {
                write!(書き先, "段の子プロセスの標準出力または標準エラーの管が開かなかった")
            }
            Self::段の出力を読めなかった(誤り) => write!(書き先, "段の子プロセスの出力を読めなかった: {誤り}"),
            Self::段の終了を待てなかった(誤り) => write!(書き先, "段の子プロセスの終了を待てなかった: {誤り}"),
            Self::段の出力を流すスレッドが落ちた => write!(書き先, "段の出力を端末とログへ流すスレッドが落ちた"),
        }
    }
}
