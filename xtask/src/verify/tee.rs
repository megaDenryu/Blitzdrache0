//! 端末とログのファイルの両方へ同じ流れを流す出力係。依存であるログのファイルをコンストラクタで保持し、
//! 流す仕事をメソッドで公開する操作サービスである。
//!
//! 子プロセスの出力を溜めてから吐く形(`output()`)を採らないのは、試験のように長い段で端末が数分無音になるためである。
//! 標準出力と標準エラーを別のスレッドで読むのは、片方の管が満杯になって子プロセスが書き込みで止まるのを防ぐためである。
//! 1つの塊を書くたびに掃き出すのは、段の途中で検証が落ちてもそこまでの出力がログに残るようにするためである。

use std::fs::File;
use std::io::{Read, Write};
use std::path::Path;
use std::process::{Command, Stdio};
use std::sync::Mutex;

use super::log_error::検証列の破れ;

/// 読み取っている管の種別。端末のどちらへ書き戻すかがこの値で決まる。
enum 流れの種別 {
    標準出力,
    標準エラー,
}

pub struct 端末とログの両方へ流す出力係 {
    ログのファイル: Mutex<File>,
}

impl 端末とログの両方へ流す出力係 {
    /// 書き足す形で開き、切り詰めないのは、このパスを`検証のログの置き場`が空のファイルを作って既に押さえているためである。
    /// 切り詰める形で開くと、押さえた側が一意にした意味が失われ、押さえの後に何かが書いた中身を消す経路が残る。
    pub fn ログのファイルを開く(パス: &Path) -> Result<Self, 検証列の破れ> {
        let ファイル = std::fs::OpenOptions::new().create(true).append(true).open(パス).map_err(|誤り| {
            検証列の破れ::ログのファイルを開けなかった {
                パス: パス.to_path_buf(),
                誤り,
            }
        })?;
        Ok(Self {
            ログのファイル: Mutex::new(ファイル),
        })
    }

    pub fn 標準出力へ行を流す(&self, 行: &str) -> Result<(), 検証列の破れ> {
        self.両方へ書く(&流れの種別::標準出力, format!("{行}\n").as_bytes())
    }

    pub fn 標準エラーへ行を流す(&self, 行: &str) -> Result<(), 検証列の破れ> {
        self.両方へ書く(&流れの種別::標準エラー, format!("{行}\n").as_bytes())
    }

    /// 子プロセスを起動し、その標準出力と標準エラーを1バイトも落とさず両方へ流す。返すのは段が成功したかである。
    pub fn 子プロセスの出力を流す(&self, 命令: &mut Command) -> Result<bool, 検証列の破れ> {
        let mut 子 = 命令
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .map_err(検証列の破れ::段の子プロセスを起動できなかった)?;
        let 標準出力 = 子.stdout.take().ok_or(検証列の破れ::段の子プロセスの出力の管が開かなかった)?;
        let 標準エラー = 子.stderr.take().ok_or(検証列の破れ::段の子プロセスの出力の管が開かなかった)?;
        let 流し切った結果 = std::thread::scope(|範囲| {
            let 出力側 = 範囲.spawn(|| self.管を最後まで流す(標準出力, &流れの種別::標準出力));
            let エラー側 = 範囲.spawn(|| self.管を最後まで流す(標準エラー, &流れの種別::標準エラー));
            スレッドの結末を畳む(出力側.join()).and(スレッドの結末を畳む(エラー側.join()))
        });
        流し切った結果?;
        let 終了状態 = 子.wait().map_err(検証列の破れ::段の終了を待てなかった)?;
        Ok(終了状態.success())
    }

    fn 管を最後まで流す(&self, mut 読み元: impl Read, 種別: &流れの種別) -> Result<(), 検証列の破れ> {
        let mut 緩衝 = [0_u8; 8192];
        loop {
            let 読めた長さ = 読み元.read(&mut 緩衝).map_err(検証列の破れ::段の出力を読めなかった)?;
            if 読めた長さ == 0 {
                return Ok(());
            }
            self.両方へ書く(種別, &緩衝[..読めた長さ])?;
        }
    }

    fn 両方へ書く(&self, 種別: &流れの種別, 塊: &[u8]) -> Result<(), 検証列の破れ> {
        match 種別 {
            流れの種別::標準出力 => 掃き出しながら書く(&mut std::io::stdout().lock(), 塊)?,
            流れの種別::標準エラー => 掃き出しながら書く(&mut std::io::stderr().lock(), 塊)?,
        }
        let mut ファイル = self
            .ログのファイル
            .lock()
            .map_err(|_| 検証列の破れ::端末かログへ書けなかった(std::io::Error::other("ログのファイルの錠が壊れている")))?;
        掃き出しながら書く(&mut *ファイル, 塊)
    }
}

fn 掃き出しながら書く(書き先: &mut dyn Write, 塊: &[u8]) -> Result<(), 検証列の破れ> {
    書き先.write_all(塊).map_err(検証列の破れ::端末かログへ書けなかった)?;
    書き先.flush().map_err(検証列の破れ::端末かログへ書けなかった)
}

/// スレッドが自分の中で落ちた場合と、流す途中で落ちた場合を1つの結末へ畳む。
fn スレッドの結末を畳む(結末: std::thread::Result<Result<(), 検証列の破れ>>) -> Result<(), 検証列の破れ> {
    結末.unwrap_or(Err(検証列の破れ::段の出力を流すスレッドが落ちた))
}
