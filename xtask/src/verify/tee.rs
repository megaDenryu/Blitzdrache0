//! 端末とログの両方へ同じ流れを流す出力係。ログが一次の記録であり、端末はその複製先である。
//! 依存であるログの書き込み先と端末への複製係をコンストラクタで保持し、流す仕事をメソッドで公開する操作サービスである。
//!
//! 子プロセスの出力を溜めてから吐く形(`output()`)を採らないのは、試験のように長い段で端末が数分無音になるためである。
//! 標準出力と標準エラーを別のスレッドで読むのは、片方の管が満杯になって子プロセスが書き込みで止まるのを防ぐためである。
//! 1つの塊を書くたびに掃き出すのは、段の途中で検証が落ちてもそこまでの出力がログに残るようにするためである。
//! ログへ先に書いてから端末へ複製するのは、端末が壊れてもログの記録が欠けないようにするためである。参照: PR #83のレビュー

mod terminal_copy;

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod terminal_failure_tests;

use std::io::{Read, Write};
use std::path::Path;
use std::process::{Command, Stdio};
use std::sync::Mutex;

use super::log_error::検証列の破れ;
use terminal_copy::{端末の流れの種別, 端末への複製係};

pub struct 端末とログの両方へ流す出力係 {
    ログの書き込み先: Mutex<Box<dyn Write + Send>>,
    端末への複製: 端末への複製係,
}

impl 端末とログの両方へ流す出力係 {
    /// 書き足す形で開き、切り詰めないのは、このパスを`検証のログの置き場`が空のファイルを作って既に押さえているためである。
    /// 切り詰める形で開くと、押さえた側が一意にした意味が失われ、押さえの後に何かが書いた中身を消す経路が残る。
    pub fn ログのファイルを開く(パス: &Path) -> Result<Self, 検証列の破れ> {
        let ファイル = std::fs::OpenOptions::new().create(true).append(true).open(パス).map_err(|誤り| {
            検証列の破れ::ログのファイルを開けなかった {
                パス: パス.to_path_buf(),
                誤り,
            }
        })?;
        Ok(Self::書き込み先を指定して作る(
            Box::new(ファイル),
            端末への複製係::本物の端末へ複製する(),
        ))
    }

    pub fn 書き込み先を指定して作る(ログの書き込み先: Box<dyn Write + Send>, 端末への複製: 端末への複製係) -> Self {
        Self {
            ログの書き込み先: Mutex::new(ログの書き込み先),
            端末への複製,
        }
    }

    pub fn 標準出力へ行を流す(&self, 行: &str) -> Result<(), 検証列の破れ> {
        self.両方へ書く(&端末の流れの種別::標準出力, format!("{行}\n").as_bytes())
    }

    pub fn 標準エラーへ行を流す(&self, 行: &str) -> Result<(), 検証列の破れ> {
        self.両方へ書く(&端末の流れの種別::標準エラー, format!("{行}\n").as_bytes())
    }

    /// 端末への複製が破れたまま終わったかを、最初の破れの説明で答える。呼び出し側はこれが答えたら結末を失敗にする。
    pub fn 端末への複製の破れ(&self) -> Option<String> {
        self.端末への複製.破れの説明()
    }

    /// 子プロセスを起動し、その標準出力と標準エラーを1バイトも落とさず流す。返すのは段が成功したかである。
    pub fn 子プロセスの出力を流す(&self, 命令: &mut Command) -> Result<bool, 検証列の破れ> {
        let mut 子 = 命令
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .map_err(検証列の破れ::段の子プロセスを起動できなかった)?;
        let 標準出力 = 子.stdout.take().ok_or(検証列の破れ::段の子プロセスの出力の管が開かなかった)?;
        let 標準エラー = 子.stderr.take().ok_or(検証列の破れ::段の子プロセスの出力の管が開かなかった)?;
        let 流し切った結果 = std::thread::scope(|範囲| {
            let 出力側 = 範囲.spawn(|| self.管を最後まで流す(標準出力, &端末の流れの種別::標準出力));
            let エラー側 = 範囲.spawn(|| self.管を最後まで流す(標準エラー, &端末の流れの種別::標準エラー));
            スレッドの結末を畳む(出力側.join()).and(スレッドの結末を畳む(エラー側.join()))
        });
        流し切った結果?;
        let 終了状態 = 子.wait().map_err(検証列の破れ::段の終了を待てなかった)?;
        Ok(終了状態.success())
    }

    /// ログへ書けなくなった後も管を読み続けて中身を捨てるのは、読むのをやめると子プロセスが管の満杯で書き込みに止まり、
    /// `wait`が返らなくなるためである。返すのは最初の破れであり、後から起きた破れでそれを上書きしない。
    fn 管を最後まで流す(&self, mut 読み元: impl Read, 種別: &端末の流れの種別) -> Result<(), 検証列の破れ> {
        let mut 緩衝 = [0_u8; 8192];
        let mut 最初の破れ: Option<検証列の破れ> = None;
        loop {
            let 読めた長さ = match 読み元.read(&mut 緩衝) {
                Ok(長さ) => 長さ,
                Err(誤り) => return Err(最初の破れ.unwrap_or(検証列の破れ::段の出力を読めなかった(誤り))),
            };
            if 読めた長さ == 0 {
                return 最初の破れ.map_or(Ok(()), Err);
            }
            if 最初の破れ.is_none() {
                最初の破れ = self.両方へ書く(種別, &緩衝[..読めた長さ]).err();
            }
        }
    }

    /// ログへ先に書き、その後で端末へ複製する。端末が初めて破れたことはログへ1行として残す。
    /// 端末の破れでこの仕事を失敗させないのは、失敗させると管を読む輪が止まり、子プロセスが管の満杯で止まるためである。
    fn 両方へ書く(&self, 種別: &端末の流れの種別, 塊: &[u8]) -> Result<(), 検証列の破れ> {
        self.ログへ書く(塊)?;
        let Some(説明) = self.端末への複製.複製して初めての破れだけを返す(種別, 塊) else {
            return Ok(());
        };
        self.ログへ書く(format!("[xtask] 端末への複製が破れたため複製を止めた: {説明}\n").as_bytes())
    }

    fn ログへ書く(&self, 塊: &[u8]) -> Result<(), 検証列の破れ> {
        let mut 書き先 = self.ログの書き込み先.lock().unwrap_or_else(|毒| 毒.into_inner());
        書き先.write_all(塊).map_err(検証列の破れ::ログへ書けなかった)?;
        書き先.flush().map_err(検証列の破れ::ログへ書けなかった)
    }
}

/// スレッドが自分の中で落ちた場合と、流す途中で落ちた場合を1つの結末へ畳む。
fn スレッドの結末を畳む(結末: std::thread::Result<Result<(), 検証列の破れ>>) -> Result<(), 検証列の破れ> {
    結末.unwrap_or(Err(検証列の破れ::段の出力を流すスレッドが落ちた))
}
