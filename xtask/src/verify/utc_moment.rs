//! 協定世界時の時刻。受け取るのは1970年1月1日0時0分0秒からの経過秒、返すのは`yyyyMMdd-HHmmss`の綴りである。
//!
//! 暦の変換を自分で書くのは、xtaskが外部のクレートへ依存しないためである(依存の白リストが暦のクレートを持たない)。
//! 変換の正しさは、うるう年・世紀のうるう年・日をまたぐ境目を含む固定の見本で単体試験が固定する。
//! 識別子に漢数字を使うのは、Rustの識別子が算用数字で始まれないためである。

use super::log_error::検証列の破れ;

/// 1日の秒数。うるう秒を持たない協定世界時の暦の上での長さである。
const 一日の秒数: u64 = 86400;

pub struct 協定世界時の時刻 {
    年: u64,
    月: u64,
    日: u64,
    時: u64,
    分: u64,
    秒: u64,
}

impl 協定世界時の時刻 {
    pub fn いまを読む() -> Result<Self, 検証列の破れ> {
        let 経過 = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_err(|_| 検証列の破れ::時計が1970年より前を指している)?;
        Ok(Self::経過秒から組み立てる(経過.as_secs()))
    }

    pub fn 経過秒から組み立てる(経過秒: u64) -> Self {
        let 通日 = 経過秒 / 一日の秒数;
        let 日内の秒 = 経過秒 % 一日の秒数;
        let (年, 月, 日) = 通日を年月日へ写す(通日);
        Self {
            年,
            月,
            日,
            時: 日内の秒 / 3600,
            分: (日内の秒 % 3600) / 60,
            秒: 日内の秒 % 60,
        }
    }

    pub fn 綴り(&self) -> String {
        let Self {
            年, 月, 日, 時, 分, 秒
        } = self;
        format!("{年:04}{月:02}{日:02}-{時:02}{分:02}{秒:02}")
    }
}

/// 1970年1月1日からの通日を年月日へ写す。3月を年の初めに置き直すと、うるう日が年の末尾へ寄って場合分けが消える。
/// 参照: Howard Hinnantの`civil_from_days`(公開領域のグレゴリオ暦の変換)。
fn 通日を年月日へ写す(通日: u64) -> (u64, u64, u64) {
    let 三月起点の通日 = 通日 + 719468;
    let 四百年紀 = 三月起点の通日 / 146097;
    let 四百年紀内の日 = 三月起点の通日 % 146097;
    let 四百年紀内の年 = (四百年紀内の日 - 四百年紀内の日 / 1460 + 四百年紀内の日 / 36524 - 四百年紀内の日 / 146096) / 365;
    let 三月起点の年 = 四百年紀内の年 + 四百年紀 * 400;
    let 年内の日 = 四百年紀内の日 - (365 * 四百年紀内の年 + 四百年紀内の年 / 4 - 四百年紀内の年 / 100);
    let 三月起点の月番号 = (5 * 年内の日 + 2) / 153;
    let 日 = 年内の日 - (153 * 三月起点の月番号 + 2) / 5 + 1;
    let 月 = if 三月起点の月番号 < 10 {
        三月起点の月番号 + 3
    } else {
        三月起点の月番号 - 9
    };
    let 年 = if 月 <= 2 { 三月起点の年 + 1 } else { 三月起点の年 };
    (年, 月, 日)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 経過秒0は1970年1月1日の0時である() {
        assert_eq!(協定世界時の時刻::経過秒から組み立てる(0).綴り(), "19700101-000000");
    }

    #[test]
    fn 日をまたぐ手前の1秒は同じ日の23時59分59秒である() {
        assert_eq!(協定世界時の時刻::経過秒から組み立てる(86399).綴り(), "19700101-235959");
    }

    #[test]
    fn うるう年の2月29日を1日として数える() {
        assert_eq!(協定世界時の時刻::経過秒から組み立てる(1582934400).綴り(), "20200229-000000");
    }

    #[test]
    fn 四百で割り切れる2000年はうるう年である() {
        assert_eq!(協定世界時の時刻::経過秒から組み立てる(951782400).綴り(), "20000229-000000");
    }

    /// 400で割り切れない世紀の年は、4で割り切れてもうるう年ではない。2100年2月の翌日が3月1日であることで固定する。
    #[test]
    fn 四百で割り切れない2100年はうるう年ではない() {
        assert_eq!(協定世界時の時刻::経過秒から組み立てる(4107456000).綴り(), "21000228-000000");
        assert_eq!(協定世界時の時刻::経過秒から組み立てる(4107542400).綴り(), "21000301-000000");
    }

    #[test]
    fn 時分秒を桁で揃えて綴る() {
        assert_eq!(協定世界時の時刻::経過秒から組み立てる(1000000000).綴り(), "20010909-014640");
    }
}
