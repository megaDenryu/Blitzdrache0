//! ストリーミング進行の終了時報告から、読込と解除の事象を起きた順に取り出す。何を事象と見なすかと、見出しごとの分解をここが所有する。
//! フレーム番号を含む行を対象から外すのは、非同期読込の完了フレームがディスクの応答時間で前後し、順序の再現とは別の量になるためである。

use crate::acceptance::終了時報告;
use crate::report_heading::報告の見出し;

pub(super) enum 突き合わせの扱い {
    合否に使う,
    観測にとどめる,
}

pub(super) struct 事象種別 {
    pub(super) 見出し: 報告の見出し,
    pub(super) 扱い: 突き合わせの扱い,
}

/// 見出しは`crates/blitz_app/src/reports/streaming.rs`が出す名前と一致させる。
///
/// 読込側を合否に使わないのは、縮退が起きる上限では読込が1件ずつ直列になり、次に読むチャンクが前の読込の完了時刻に依存するためである。
/// プレイヤー位置はフレーム番号で決まるがディスクの応答時間は決まらないため、両者の相対関係が実行ごとに変わりうる。
/// 予算が拘束しない上限では読込順も含めて完全に一致することを実測で確かめてある(参照: `_doc/計測/OW2第10段_2026-07-26.md`)。
pub(super) const 事象種別一覧: [事象種別; 4] = [
    事象種別 {
        見出し: 報告の見出し::定数から生成する("読込開始:"),
        扱い: 突き合わせの扱い::観測にとどめる,
    },
    事象種別 {
        見出し: 報告の見出し::定数から生成する("準備完了:"),
        扱い: 突き合わせの扱い::観測にとどめる,
    },
    事象種別 {
        見出し: 報告の見出し::定数から生成する("CPUデータ破棄:"),
        扱い: 突き合わせの扱い::合否に使う,
    },
    事象種別 {
        見出し: 報告の見出し::定数から生成する("GPU資源解除待ち:"),
        扱い: 突き合わせの扱い::合否に使う,
    },
];

pub(super) fn 事象列を取り出す(報告: &終了時報告) -> Vec<String> {
    let 見出し一覧: Vec<報告の見出し> = 事象種別一覧.iter().map(|種別| 種別.見出し.clone()).collect();
    報告
        .いずれかの見出しで始まる行の一覧(&見出し一覧)
        .iter()
        .map(|行| 行.原文().to_string())
        .collect()
}

/// 1つの見出しの事象だけを起きた順に取り出す。見出しをまたいだ並びは読込完了の時刻で前後するため、比較は見出しごとに行う。
pub(super) fn 見出しで絞る(事象列: &[String], 見出し: &報告の見出し) -> Vec<String> {
    事象列.iter().filter(|行| 見出し.行の始まりか(行)).cloned().collect()
}

/// 1行が複数の座標を並べるため、件数は行数ではなくチャンク座標の出現数で数える。
pub(super) fn 座標数を数える(事象列: &[String]) -> usize {
    事象列.iter().map(|行| 行.matches("(x=").count()).sum()
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;
    use crate::acceptance::検収の実行名;

    const 標本の実行名: 検収の実行名 = 検収の実行名::定数から生成する("streaming_order");

    #[test]
    fn 事象行だけをフレーム番号なしで取り出す() {
        let 出力 = "ストリーミング進行(フレーム3):\n  台帳登録数: 9\n  読込開始: (x=0, z=0)\n  予算判定: 全件収容\n";
        let 報告 = 終了時報告::取り込む(&標本の実行名, 出力.to_string(), String::new());
        assert_eq!(事象列を取り出す(&報告), vec!["読込開始: (x=0, z=0)".to_string()]);
    }

    #[test]
    fn 見出しで絞ると他の種類は残らない() {
        let 事象列 = vec!["読込開始: (x=0, z=0)".to_string(), "準備完了: (x=0, z=0)".to_string()];
        let 見出し = 報告の見出し::定数から生成する("準備完了:");
        assert_eq!(見出しで絞る(&事象列, &見出し), vec!["準備完了: (x=0, z=0)".to_string()]);
    }

    #[test]
    fn 一行に並ぶ座標をすべて数える() {
        let 事象列 = vec!["読込開始: (x=0, z=0) (x=1, z=0)".to_string()];
        assert_eq!(座標数を数える(&事象列), 2);
    }
}
