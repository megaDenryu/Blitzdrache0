//! 2回の実行の事象列を突き合わせ、どこまで一致したかを表示する。合否の基準をここが所有する。
//!
//! 合否は縮退で外周が落ちる順序、すなわちCPUデータ破棄と解除待ちの列で決める。条件Bが観測しようとしている量がそれだからである。
//! 読込側の列は表示するが合否には使わない。理由は`order_sequence`の事象種別一覧に書いた。
//! 種類をまたいで混ぜた1本の列も合否に使わない。準備完了はワーカースレッドの読込完了時刻で前後し、その前後は読込順とも解除順とも別の量だからである。

use super::order_sequence::{事象種別一覧, 座標数を数える, 突き合わせの扱い, 見出しで絞る};

enum 順序比較 {
    一致 {
        座標数: usize,
    },
    相違 {
        位置: usize,
        一回目: Option<String>,
        二回目: Option<String>,
    },
}

/// 合否に使う見出しの列がすべて一致したときだけ真を返す。
pub(super) fn 突き合わせて表示する(一回目: &[String], 二回目: &[String]) -> bool {
    let mut 合否 = true;
    for 種別 in &事象種別一覧 {
        let 左 = 見出しで絞る(一回目, 種別.見出し);
        let 右 = 見出しで絞る(二回目, 種別.見出し);
        let 一致した = 一件を表示する(種別.見出し, &比べる(&左, &右));
        match 種別.扱い {
            突き合わせの扱い::合否に使う => 合否 &= 一致した,
            突き合わせの扱い::観測にとどめる => {}
        }
    }
    println!("  参考(種類を混ぜた1本の列、合否には使わない):");
    一件を表示する("全事象", &比べる(一回目, 二回目));
    合否
}

fn 比べる(一回目: &[String], 二回目: &[String]) -> 順序比較 {
    for 位置 in 0..一回目.len().max(二回目.len()) {
        let (左, 右) = (一回目.get(位置), 二回目.get(位置));
        if 左 != 右 {
            return 順序比較::相違 {
                位置,
                一回目: 左.cloned(),
                二回目: 右.cloned(),
            };
        }
    }
    順序比較::一致 {
        座標数: 座標数を数える(一回目),
    }
}

fn 一件を表示する(名前: &str, 比較: &順序比較) -> bool {
    match 比較 {
        順序比較::一致 { 座標数 } => {
            println!("  {名前} 一致({座標数}件)");
            true
        }
        順序比較::相違 {
            位置, 一回目, 二回目
        } => {
            println!("  {名前} {位置}行目で相違");
            println!("    1回目: {}", 行を表す(一回目.as_deref()));
            println!("    2回目: {}", 行を表す(二回目.as_deref()));
            false
        }
    }
}

fn 行を表す(行: Option<&str>) -> String {
    match 行 {
        Some(行) => 行.to_string(),
        None => "その位置に事象が無い".to_string(),
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn 読込順が違っても解除順が同じなら合否は真になる() {
        let 一回目 = vec!["読込開始: (x=0, z=0)".to_string(), "GPU資源解除待ち: (x=9, z=9)".to_string()];
        let 二回目 = vec!["読込開始: (x=1, z=0)".to_string(), "GPU資源解除待ち: (x=9, z=9)".to_string()];
        assert!(突き合わせて表示する(&一回目, &二回目));
    }

    #[test]
    fn 解除順が違えば合否は偽になる() {
        let 一回目 = vec!["GPU資源解除待ち: (x=0, z=0)".to_string()];
        let 二回目 = vec!["GPU資源解除待ち: (x=1, z=0)".to_string()];
        assert!(!突き合わせて表示する(&一回目, &二回目));
    }
}
