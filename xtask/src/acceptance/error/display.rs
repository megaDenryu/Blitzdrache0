//! 検収エラーを人が読む1文へ写すトレイト実装。枝ごとに、破れた前提と次に見る場所が分かる文面にする。
//! 実装を型の定義と分けるのは、外部トレイトの実装が型自身の持ち物とは別の軸であるためである。

use std::fmt;

use super::検収エラー;

impl fmt::Display for 検収エラー {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::出力ディレクトリを作れなかった { パス, 誤り } => {
                write!(書き手, "{}を作れなかった: {誤り}", パス.display())
            }
            Self::アプリを起こせなかった {
                実行名, 起こし方, 誤り
            } => write!(書き手, "{起こし方}でblitz_appを起動できなかった({実行名}): {誤り}"),
            Self::アプリが失敗して終わった { 実行名, 終了状態 } => {
                write!(書き手, "blitz_appが{終了状態}で失敗した({実行名})")
            }
            Self::検証層の指摘が残った { 実行名, 件数 } => {
                write!(書き手, "{実行名}でvalidationが{件数}件発生した")
            }
            Self::報告の読み取りが破れた { 実行名, 破れ } => write!(書き手, "{実行名}の{破れ}"),
            Self::読み戻しが破れた(破れ) => write!(書き手, "{破れ}"),
            Self::判定が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::予約された選択肢を汎用の口から積んだ { 綴り, 予約の一覧 } => write!(
                書き手,
                "型が組み立てる選択肢{綴り}を汎用の口から積んだ(型が組み立てるのは{予約の一覧}であり、これらは起動指定の構築の口が渡す)"
            ),
            Self::割合が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::検収の実行名が空である => write!(書き手, "検収の実行名が空である"),
            Self::検収の実行名が使えない文字を含む { 名前, 文字 } => {
                write!(
                    書き手,
                    "検収の実行名が使えない文字{文字:?}を含む(置けるのは英数字と下線とハイフンだけである): {名前}"
                )
            }
            Self::検収の実行名が予約された装置の名前である { 名前 } => {
                write!(書き手, "検収の実行名がWindowsの予約された装置の名前である: {名前}")
            }
            Self::目視用の絵へ変換できなかった { 書き出し先, 破れ } => {
                write!(書き手, "{}を目視用の絵へ変換できなかった: {破れ}", 書き出し先.display())
            }
        }
    }
}
