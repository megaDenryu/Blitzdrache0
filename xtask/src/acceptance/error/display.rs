//! 検収エラーを人が読む1文へ写すトレイト実装。枝ごとに、破れた前提と次に見る場所が分かる文面にする。
//! 実装を型の定義と分けるのは、外部トレイトの実装が型自身の持ち物とは別の軸であるためである。

use std::fmt;

use super::検収エラー;

impl fmt::Display for 検収エラー {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::出力ディレクトリを作れなかった { パス, 誤り } => {
                write!(書き手, "{}を作れなかった: {誤り}", パス.display())
            }
            Self::アプリを起こせなかった {
                条件名, 起こし方, 誤り
            } => write!(書き手, "{起こし方}でblitz_appを起動できなかった({条件名}): {誤り}"),
            Self::アプリが失敗して終わった { 条件名, 終了状態 } => {
                write!(書き手, "blitz_appが{終了状態}で失敗した({条件名})")
            }
            Self::検証層の指摘が残った { 条件名, 件数 } => {
                write!(書き手, "{条件名}でvalidationが{件数}件発生した")
            }
            Self::報告に見出しの行が無い {
                読み手の名前, 見出し
            } => {
                write!(書き手, "{読み手の名前}の出力に「{見出し}」の行が無い")
            }
            Self::報告の値を数として読めない {
                読み手の名前, 見出し, 本文
            } => write!(書き手, "{読み手の名前}の「{見出し}」の値を数として読めない: {本文}"),
            Self::読み戻しのファイルを読めない { パス, 誤り } => {
                write!(書き手, "{}を読めない: {誤り}", パス.display())
            }
            Self::読み戻しの寸法が幅と高さの2数でない { パス, 本文 } => {
                write!(書き手, "{}の寸法が「幅 高さ」の2数でない: {本文}", パス.display())
            }
            Self::読み戻しの寸法がバイト長へ収まらない { 幅, 高さ } => {
                write!(書き手, "読み戻し画像の寸法{幅}×{高さ}がバイト長へ収まらない")
            }
            Self::読み戻しの寸法とバイト長が食い違う {
                寸法から求めたバイト長,
                実際のバイト長,
            } => write!(書き手, "寸法とRGBA8長が違う: {寸法から求めたバイト長}と{実際のバイト長}"),
            Self::目視用の絵へ変換できなかった { 書き出し先, 理由 } => {
                write!(書き手, "{}を目視用の絵へ変換できなかった: {理由}", 書き出し先.display())
            }
        }
    }
}
