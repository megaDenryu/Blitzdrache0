//! 読み戻しの破れ: 書き出されたファイルを絵として読むときに破れうる前提を数え上げた型。
//!
//! 検収エラーの枝を平らに並べず1つの型へ束ねるのは、この7つが同じ場所(書き出されたファイルを読む工程)の
//! 語彙であり、他の枝と混ざると「どの段で落ちたか」が枝の数だけ散るためである。8ビットの読み戻しと
//! 明るさの圧縮前の読み戻しが、寸法の読み取りだけを共有して残りは別々に破れることも、この束が示す。
//!
//! 数え上げをバイトと成分で分けるのは、単位が違うためである。片方の数をもう片方の枝へ渡すと、
//! 文面が「バイト長」と言いながら成分数を出す。

use std::path::PathBuf;

/// `バイト長が成分の境界で終わっていない`は、単精度の読み戻しのバイト長が4の倍数で終わっていない形である。
/// 端数を捨てて読むと、正しい長さへ数バイト足されたファイルが端数を落とした後の成分数で寸法と一致し、
/// 壊れた書き出しのまま構築を通ってしまう。
#[derive(Debug)]
pub enum 読み戻しの破れ {
    ファイルを読めない {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    寸法が幅と高さの2数でない {
        パス: PathBuf,
        本文: String,
    },
    寸法がバイト長へ収まらない {
        幅: usize,
        高さ: usize,
    },
    寸法とバイト長が食い違う {
        寸法から求めたバイト長: usize,
        実際のバイト長: usize,
    },
    バイト長が成分の境界で終わっていない {
        パス: PathBuf,
        バイト長: usize,
    }, // バイト長が4の倍数で終わっていない
    寸法が成分の数へ収まらない {
        幅: usize,
        高さ: usize,
    },
    寸法と成分の数が食い違う {
        寸法から求めた成分数: usize,
        実際の成分数: usize,
    },
}

impl std::fmt::Display for 読み戻しの破れ {
    fn fmt(&self, 書き手: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::ファイルを読めない { パス, 誤り } => write!(書き手, "{}を読めない: {誤り}", パス.display()),
            Self::寸法が幅と高さの2数でない { パス, 本文 } => {
                write!(書き手, "{}の寸法が「幅 高さ」の2数でない: {本文}", パス.display())
            }
            Self::寸法がバイト長へ収まらない { 幅, 高さ } => {
                write!(書き手, "読み戻し画像の寸法{幅}×{高さ}がバイト長へ収まらない")
            }
            Self::寸法とバイト長が食い違う {
                寸法から求めたバイト長,
                実際のバイト長,
            } => write!(書き手, "寸法とRGBA8長が違う: {寸法から求めたバイト長}と{実際のバイト長}"),
            Self::バイト長が成分の境界で終わっていない { パス, バイト長 } => {
                write!(書き手, "{}のバイト長{バイト長}が単精度4バイトの境界で終わっていない", パス.display())
            }
            Self::寸法が成分の数へ収まらない { 幅, 高さ } => {
                write!(書き手, "圧縮前のHDR画像の寸法{幅}×{高さ}が成分の数へ収まらない")
            }
            Self::寸法と成分の数が食い違う {
                寸法から求めた成分数,
                実際の成分数,
            } => write!(書き手, "寸法と単精度の成分数が違う: {寸法から求めた成分数}と{実際の成分数}"),
        }
    }
}
