//! 判定の破れ: 検収の判定が落ちたときに、どの判定がどう破れたかを言う型。
//!
//! 枝を検収エラーへ平らに並べず1つの型へ束ねるのは、61の入口の判定が落ちる形が、名前と数の違いを除けば
//! 9通りしかないためである。実測では判定の失敗が541箇所の`Result<_, String>`へ散っており、
//! 同じ「上限を超えた」がそれぞれの文面で書かれていた。破れの形をここが数え上げ、
//! 何の判定かは`判定の名前`が、比べた数は`判定が比べる値`が持つ。
//!
//! 実測と期待を型のまま持つのは、文へ焼いてから持つと役割の取り違え(下限の数を上限として出す)が
//! 文面にしか現れないためである。人が読む1文へ写すのは`display`が持つ。

mod display;

use super::super::judgment_name::判定の名前;
use super::super::judgment_value::判定が比べる値;

#[derive(Debug)]
pub struct 判定の破れ {
    判定の名前: 判定の名前,
    種類: 判定の破れの種類,
}

#[derive(Debug)]
pub enum 判定の破れの種類 {
    上限を超えた {
        実測: 判定が比べる値, 上限: 判定が比べる値
    },
    下限に届かない {
        実測: 判定が比べる値, 下限: 判定が比べる値
    },
    許容の範囲を外れた {
        実測: 判定が比べる値,
        下限: 判定が比べる値,
        上限: 判定が比べる値,
    },
    一致するはずが食い違った {
        実測: 判定が比べる値, 期待: 判定が比べる値
    },
    /// 零件であることを課した判定に件数が残った。validationの指摘や、動いてはならない画素の数がこれである。
    零件のはずが残った { 件数: 判定が比べる値 },
    /// 1件以上あることを課した判定に何も無かった。件数0で表すと、続く統計が意味を持たないまま消費側へ渡る。
    あるはずのものが1件も無い,
    /// 有限でない実測が来た。非数と無限大は上限にも下限にも収まらないまま比べを素通りするため、
    /// 大小を課した判定はこの枝で落とす。
    有限でない { 実測: 判定が比べる値 },
    /// 正であることを課した判定に零か負が来た。比の分母がこれになると答えが非数か無限大になる。
    正でない { 実測: 判定が比べる値 },
    /// 判定の材料に置いた綴りを数として読めない。報告が出した表記が判定の想定する書式でない。
    材料を数として読めない { 材料: 判定が比べる値 },
}

impl 判定の破れ {
    pub(in crate::acceptance) fn 名前と種類から組み立てる(判定の名前: 判定の名前, 種類: 判定の破れの種類) -> Self {
        Self { 判定の名前, 種類 }
    }
}
