//! 判定の破れを人が読む1文へ写すトレイト実装。枝ごとに、何の判定がどう破れたかと、比べた数の両側を出す。
//! 実装を型の定義と分けるのは、外部トレイトの実装が型自身の持ち物とは別の軸であるためである。

use std::fmt;

use super::{判定の破れ, 判定の破れの種類};

impl fmt::Display for 判定の破れ {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        let 名前 = &self.判定の名前;
        match &self.種類 {
            判定の破れの種類::上限を超えた { 実測, 上限 } => {
                write!(書き手, "{名前}が{実測}で、上限{上限}を超えた")
            }
            判定の破れの種類::下限に届かない { 実測, 下限 } => {
                write!(書き手, "{名前}が{実測}で、下限{下限}に届かない")
            }
            判定の破れの種類::許容の範囲を外れた { 実測, 下限, 上限 } => {
                write!(書き手, "{名前}が{実測}で、許容の範囲{下限}以上{上限}以下から外れた")
            }
            判定の破れの種類::一致するはずが食い違った { 実測, 期待 } => {
                write!(書き手, "{名前}が{実測}であり、一致するはずの{期待}と食い違った")
            }
            判定の破れの種類::零件のはずが残った { 件数 } => {
                write!(書き手, "{名前}が{件数}件あり、零件でない")
            }
            判定の破れの種類::あるはずのものが1件も無い => write!(書き手, "{名前}が1件も無い"),
            判定の破れの種類::有限でない { 実測 } => write!(書き手, "{名前}の実測{実測}が有限でない"),
            判定の破れの種類::正でない { 実測 } => write!(書き手, "{名前}の実測{実測}が正でない"),
            判定の破れの種類::材料を数として読めない { 材料 } => {
                write!(書き手, "{名前}の材料{材料}を数として読めない")
            }
        }
    }
}
