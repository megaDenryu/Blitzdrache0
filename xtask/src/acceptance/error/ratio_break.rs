//! 割合の破れ: 画素の数どうしの比を求める段で破れうる前提を数え上げた型。
//!
//! 検収エラーの枝を平らに並べず1つの型へ束ねるのは、この2つが同じ場所(部分と全体から比を求める工程)の語彙であり、
//! どちらも「割合を返せなかった」という同じ結末を持つためである。

#[derive(Debug)]
pub enum 割合の破れ {
    全体が零である { 部分: usize }, // 零で割った割合は無限大になり、上限にも下限にも収まらないまま判定を素通りする
    画素数が計算へ収まらない { 部分: usize, 全体: usize },
}

impl std::fmt::Display for 割合の破れ {
    fn fmt(&self, 書き手: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::全体が零である { 部分 } => write!(書き手, "割合の全体が零である(部分は{部分}画素)"),
            Self::画素数が計算へ収まらない { 部分, 全体 } => {
                write!(書き手, "画素数{部分}と{全体}が割合の計算へ収まらない")
            }
        }
    }
}
