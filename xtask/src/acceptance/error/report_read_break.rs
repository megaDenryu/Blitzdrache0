//! 報告の読み取りの破れ: アプリの終了時報告から数を取り出すときに破れうる前提を数え上げた型。
//!
//! 検収エラーの枝を平らに並べず1つの型へ束ねるのは、この6つが同じ場所(報告の行から値を読む工程)の語彙であり、
//! 実測ではこの6通りが61の入口でそれぞれの文面で書かれていたためである。
//!
//! 「行が無い」と「行はあるが読めない」を別の枝で持つのは、直す側が見る場所が違うためである。
//! 前者はアプリが行を出していないか綴りが食い違っており、後者は行の書式が変わっている。

use crate::report_heading::報告の見出し;
use crate::report_line_key::報告の行の鍵;

#[derive(Debug)]
pub enum 報告の読み取りの破れ {
    見出しの行が無い {
        見出し: 報告の見出し,
    },
    /// 見出しで囲まれた区画の中に、探した接頭辞で始まる行が無い。同じ綴りの行が別の区画にも出るため、
    /// 区画を切ってから探す読み取りがこの枝を返す。
    区画に接頭辞の行が無い {
        見出し: 報告の見出し,
        接頭辞: 報告の見出し,
    },
    行に鍵が無い {
        行: String,
        鍵: 報告の行の鍵,
    },
    鍵の次に語が無い {
        行: String,
        鍵: 報告の行の鍵,
    },
    鍵に続く語を数として読めない {
        行: String,
        鍵: 報告の行の鍵,
        語: String,
    },
    /// 真偽で答える行の値が「真」でも「偽」でもない。アプリ側の綴りが変わった印である。
    鍵に続く語が真でも偽でもない {
        行: String,
        鍵: 報告の行の鍵,
        語: String,
    },
    見出しに続く本文を数として読めない {
        見出し: 報告の見出し,
        本文: String,
    },
    /// 「見出し: 0=9 1=6」の形で並ぶはずの項が、添字と値の対になっていない。
    見出しに続く項が添字と値の対でない {
        見出し: 報告の見出し,
        項: String,
    },
    /// 添字が0から1つずつ増える並びになっていない。飛んだ添字を詰めて読むと、別の添字の値を返す。
    見出しに続く添字が0から昇順に並んでいない {
        見出し: 報告の見出し,
        本文: String,
    },
}

impl std::fmt::Display for 報告の読み取りの破れ {
    fn fmt(&self, 書き手: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::見出しの行が無い { 見出し } => write!(書き手, "報告に「{見出し}」の行が無い"),
            Self::区画に接頭辞の行が無い { 見出し, 接頭辞 } => {
                write!(書き手, "報告の「{見出し}」の区画に「{接頭辞}」で始まる行が無い")
            }
            Self::行に鍵が無い { 行, 鍵 } => write!(書き手, "「{行}」に鍵{鍵}が無い"),
            Self::鍵の次に語が無い { 行, 鍵 } => write!(書き手, "「{行}」の鍵{鍵}の次に語が無い"),
            Self::鍵に続く語を数として読めない { 行, 鍵, 語 } => {
                write!(書き手, "「{行}」の鍵{鍵}に続く語{語}を数として読めない")
            }
            Self::鍵に続く語が真でも偽でもない { 行, 鍵, 語 } => {
                write!(書き手, "「{行}」の鍵{鍵}に続く語{語}が真でも偽でもない")
            }
            Self::見出しに続く本文を数として読めない { 見出し, 本文 } => {
                write!(書き手, "「{見出し}」に続く本文{本文}を数として読めない")
            }
            Self::見出しに続く項が添字と値の対でない { 見出し, 項 } => {
                write!(書き手, "「{見出し}」に続く項{項}が添字と値の対でない")
            }
            Self::見出しに続く添字が0から昇順に並んでいない { 見出し, 本文 } => {
                write!(書き手, "「{見出し}」に続く添字が0から昇順に並んでいない: {本文}")
            }
        }
    }
}
