//! アプリの起動指定: 1回ぶんの起動でアプリへ渡す、シーンと枚数と選択肢を組み立てる型。
//!
//! 構築をビルダーの形にするのは、条件ごとに足す選択肢の数と種類が違い、しかもシーンと枚数は
//! どの条件でも必ず要るためである。必ず要る2つを構築の口で受け、任意の選択肢だけをメソッドの連鎖で足すと、
//! シーンを決めないまま起動できる半端な状態が作れない。
//!
//! 完成させるメソッドを別に置かないのは、この型自身が完成物であるためである。
//! アセットルートと書き出し先は条件ごとに変わらないため、この型でなく実行環境の側が足す。
//!
//! 選択肢を`OsString`で溜めるのは、値にパスを取る選択肢(監視対象シェーダーの入口等)があるためである。
//! `String`で溜めると、パスを綴りへ写す工程が呼び出し側に散り、写せない綴りの扱いが入口ごとに分かれる。

use std::ffi::OsString;
use std::path::Path;
use std::process::Command;

use super::draw_end::描き終わりの決め方;
use super::frame_count::描画フレーム数;
use super::scene_name::検収シーン名;

pub struct アプリの起動指定 {
    シーン名: 検収シーン名,
    描き終わり: 描き終わりの決め方,
    追加の選択肢: Vec<OsString>,
}

impl アプリの起動指定 {
    pub fn シーンと枚数を決める(シーン名: 検収シーン名, フレーム数: 描画フレーム数) -> Self {
        Self {
            シーン名,
            描き終わり: 描き終わりの決め方::枚数を描き切る(フレーム数),
            追加の選択肢: Vec::new(),
        }
    }

    /// 計測窓として決めた枚数を描かせる。スモーク実行の自己操作を1つも入れない。
    pub fn シーンと計測の枚数を決める(シーン名: 検収シーン名, フレーム数: 描画フレーム数) -> Self {
        Self {
            シーン名,
            描き終わり: 描き終わりの決め方::計測の枚数を描き切る(フレーム数),
            追加の選択肢: Vec::new(),
        }
    }

    /// 枚数を決めず、人が画面を閉じるまで描かせる。遊ぶ入口だけがこの口を通る。
    pub fn シーンを決めて人が終えるまで描かせる(シーン名: 検収シーン名) -> Self {
        Self {
            シーン名,
            描き終わり: 描き終わりの決め方::人が終えるまで描き続ける,
            追加の選択肢: Vec::new(),
        }
    }

    /// 値を持たない選択肢を1つ足す。
    pub fn 選択肢を足す(mut self, 綴り: &str) -> Self {
        self.追加の選択肢.push(OsString::from(綴り));
        self
    }

    /// 値を持たない選択肢をまとめて足す。条件ごとの並びを1つの配列で持つ入口のための口である。
    pub fn 選択肢をまとめて足す(mut self, 綴り一覧: &[&str]) -> Self {
        self.追加の選択肢.extend(綴り一覧.iter().map(OsString::from));
        self
    }

    /// 値を1つ取る選択肢を足す。選択肢とその値を離して足せる口を作らないのは、
    /// 値だけが抜けた指定が組み上がるとアプリ側で別の選択肢の値として読まれるためである。
    pub fn 値を持つ選択肢を足す(mut self, 綴り: &str, 値: &str) -> Self {
        self.追加の選択肢.push(OsString::from(綴り));
        self.追加の選択肢.push(OsString::from(値));
        self
    }

    /// 値にパスを取る選択肢を足す。綴りへ写さずに渡すのは、写せない綴りのパスを黙って落とさないためである。
    pub fn パスを値に持つ選択肢を足す(mut self, 綴り: &str, 値: &Path) -> Self {
        self.追加の選択肢.push(OsString::from(綴り));
        self.追加の選択肢.push(値.as_os_str().to_os_string());
        self
    }

    /// その選択肢を積んであるか。「この起動指定は必ずXを外す」という決め事を検査が固定するための問いである。
    ///
    /// 注意: 今のところ読み手は回帰検査だけである。本体の経路から呼ばれるまでは`cfg(test)`で閉じる。
    #[cfg(test)]
    pub fn 選択肢を含むか(&self, 綴り: &str) -> bool {
        self.追加の選択肢.iter().any(|積んだ綴り| 積んだ綴り == 綴り)
    }

    pub(super) fn コマンドへ並べる(&self, コマンド: &mut Command) {
        コマンド.args(["--scene", self.シーン名.綴り()]);
        self.描き終わり.コマンドへ並べる(コマンド);
        コマンド.args(&self.追加の選択肢);
    }
}
