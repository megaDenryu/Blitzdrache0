//! アプリの起動指定: 1回ぶんの起動でアプリへ渡す、シーンと枚数と選択肢を組み立てる型。
//!
//! 構築をビルダーの形にするのは、条件ごとに足す選択肢の数と種類が違い、しかもシーンと枚数は
//! どの条件でも必ず要るためである。必ず要る2つを構築の口で受け、任意の選択肢だけをメソッドの連鎖で足すと、
//! シーンを決めないまま起動できる半端な状態が作れない。
//!
//! 汎用の口へ積まれた綴りが型の組み立てる選択肢と衝突していないかを、積むたびに見て最初の破れを覚える。
//! 破れは完成させる操作(`コマンドへ並べる`)が型付きエラーで返す。積む口は`option_stack`が、
//! 判定の中身と予約の一覧は`reserved_option`が持つ。
//!
//! 選択肢を`OsString`で溜めるのは、値にパスを取る選択肢(監視対象シェーダーの入口等)があるためである。
//! `String`で溜めると、パスを綴りへ写す工程が呼び出し側に散り、写せない綴りの扱いが入口ごとに分かれる。

mod option_stack;
#[cfg(test)]
mod reserved_tests;

use std::ffi::OsString;
use std::process::Command;

use super::draw_end::描き終わりの決め方;
use super::error::検収エラー;
use super::frame_count::描画フレーム数;
use super::reserved_option::予約された選択肢の綴り一覧;
use super::scene_name::検収シーン名;

/// シーンをアプリへ渡す選択肢の綴り。生の綴りが在るのはこの1行だけである。
pub(super) const シーンの選択肢の綴り: &str = "--scene";

pub struct アプリの起動指定 {
    シーン名: 検収シーン名,
    描き終わり: 描き終わりの決め方,
    追加の選択肢: Vec<OsString>,
    /// 汎用の口へ積まれた予約された選択肢のうち、最初に見つかったもの。
    予約を積んだ綴り: Option<String>,
}

impl アプリの起動指定 {
    pub fn シーンと枚数を決める(シーン名: 検収シーン名, フレーム数: 描画フレーム数) -> Self {
        Self::始める(シーン名, 描き終わりの決め方::枚数を描き切る(フレーム数))
    }

    /// 計測窓として決めた枚数を描かせる。スモーク実行の自己操作を1つも入れない。
    pub fn シーンと計測の枚数を決める(シーン名: 検収シーン名, フレーム数: 描画フレーム数) -> Self {
        Self::始める(シーン名, 描き終わりの決め方::計測の枚数を描き切る(フレーム数))
    }

    /// 枚数を決めず、人が画面を閉じるまで描かせる。遊ぶ入口だけがこの口を通る。
    pub fn シーンを決めて人が終えるまで描かせる(シーン名: 検収シーン名) -> Self {
        Self::始める(シーン名, 描き終わりの決め方::人が終えるまで描き続ける)
    }

    fn 始める(シーン名: 検収シーン名, 描き終わり: 描き終わりの決め方) -> Self {
        Self {
            シーン名,
            描き終わり,
            追加の選択肢: Vec::new(),
            予約を積んだ綴り: None,
        }
    }

    /// 完成させる操作。積んだ選択肢に型の組み立てる選択肢が混じっていれば、ここで型付きエラーを返す。
    pub(super) fn コマンドへ並べる(&self, コマンド: &mut Command) -> Result<(), 検収エラー> {
        if let Some(綴り) = &self.予約を積んだ綴り {
            return Err(検収エラー::予約された選択肢を汎用の口から積んだ {
                綴り: 綴り.clone(),
                予約の一覧: 予約された選択肢の綴り一覧().join(" "),
            });
        }
        コマンド.args([シーンの選択肢の綴り, self.シーン名.綴り()]);
        self.描き終わり.コマンドへ並べる(コマンド);
        コマンド.args(&self.追加の選択肢);
        Ok(())
    }
}
