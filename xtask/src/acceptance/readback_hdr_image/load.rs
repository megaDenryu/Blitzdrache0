//! 書き出された対の2ファイルを1つの圧縮前のHDR画像へ写す工程。受け取るのは書き出し先、返すのは画像である。
//! 担当するのは、寸法と成分の2ファイルを読んで単精度の並びへ開くことだけである。
//! 成分の数が寸法と合っていることの確認は、この型の不変条件として構築の口が持つ。

use std::path::Path;

use super::super::dump_format::書き出しの形式;
use super::super::error::{検収エラー, 読み戻しの破れ};
use super::super::readback_dump::読み戻しの書き出し先;
use super::super::readback_size::幅と高さを読む;
use super::圧縮前のHDR画像;

/// 1成分あたりのバイト数。単精度の4バイトである。
const 成分あたりのバイト数: usize = 4;

pub(super) fn 対の2ファイルから読み込む(
    書き出し先: &読み戻しの書き出し先
) -> Result<圧縮前のHDR画像, 検収エラー> {
    let (幅, 高さ) = 幅と高さを読む(書き出し先)?;
    let 画素のパス = 書き出し先.形式のパス(書き出しの形式::明るさの圧縮前);
    let バイト列 = std::fs::read(&画素のパス).map_err(|誤り| {
        検収エラー::読み戻しが破れた(読み戻しの破れ::ファイルを読めない {
            パス: 画素のパス.clone(),
            誤り,
        })
    })?;
    圧縮前のHDR画像::検証して組み立てる(幅, 高さ, 単精度へ開く(&バイト列, &画素のパス)?)
}

/// リトルエンディアンの4バイトずつを単精度として読む。
///
/// 注意: 端数のバイトを捨ててはならない。捨てると、正しい長さへ1から3バイト足されたファイルが、
/// 端数を落とした後の成分数で寸法と一致し、壊れた書き出しのまま構築を通ってしまう。
/// 4の倍数で終わっていないことは書き出しの破れであり、成分へ開く前にここで落とす。
pub(super) fn 単精度へ開く(バイト列: &[u8], パス: &Path) -> Result<Vec<f32>, 検収エラー> {
    if !バイト列.len().is_multiple_of(成分あたりのバイト数) {
        return Err(検収エラー::読み戻しが破れた(
            読み戻しの破れ::バイト長が成分の境界で終わっていない {
                パス: パス.to_path_buf(),
                バイト長: バイト列.len(),
            },
        ));
    }
    Ok(バイト列
        .chunks_exact(成分あたりのバイト数)
        .map(|語| f32::from_le_bytes([語[0], 語[1], 語[2], 語[3]]))
        .collect())
}
