//! 圧縮前のHDR画像の不変条件と、バイト列を成分へ開く工程の回帰検査。呼ばれるのは`cargo test`だけである。
//!
//! 端数のバイトを検査するのは、正しい長さへ1から3バイト足されたファイルが、端数を落とした後の成分数で
//! 寸法と一致してしまうためである。落とす実装では、この破れが1つも判定に現れない。
//!
//! 寸法の比較を積でなく幅と高さで見るのは、2×2と1×4が同じ積を持つためである。積で通すと、
//! 同じ添字が別の場所を指したまま2枚の突き合わせが成立する。

#![allow(clippy::unwrap_used)]

use super::load::単精度へ開く;
use super::圧縮前のHDR画像;
use std::path::Path;

/// 幅2・高さ1の絵ちょうどの成分列。RGBAの4成分であるため1画素あたり4つである。
fn 二画素ぶんの成分列() -> Vec<f32> {
    vec![0.0; 8]
}

fn 検査のパス() -> &'static Path {
    Path::new("target/test/hdr_boundary_check.hdr32")
}

#[test]
fn 寸法と成分の数が合う構築は通る() {
    let 画像 = 圧縮前のHDR画像::テスト用に作る(2, 1, 二画素ぶんの成分列()).unwrap();
    assert_eq!(画像.画素数(), 2);
    assert_eq!(画像.寸法の綴り(), "2×1");
}

#[test]
fn 成分列が短い構築は拒まれる() {
    let 結果 = 圧縮前のHDR画像::テスト用に作る(2, 1, vec![0.0; 4]);
    assert!(結果.is_err(), "1画素ぶんしかない成分列が2画素の絵として通った");
}

#[test]
fn 寸法が成分の数へ収まらない構築は拒まれる() {
    let 結果 = 圧縮前のHDR画像::テスト用に作る(usize::MAX, 2, Vec::new());
    assert!(結果.is_err(), "掛け算が溢れる寸法が通った");
}

#[test]
fn 面積が同じで縦横が違う2枚は寸法が違うと判定される() {
    let 縦長 = 圧縮前のHDR画像::テスト用に作る(2, 2, vec![0.0; 16]).unwrap();
    let 横長 = 圧縮前のHDR画像::テスト用に作る(1, 4, vec![0.0; 16]).unwrap();
    assert_eq!(縦長.画素数(), 横長.画素数(), "この検査の前提である「積が同じ」が成り立っていない");
    assert!(!縦長.寸法が同じか(&横長), "2×2と1×4が同じ寸法として通った");
}

#[test]
fn 同じ寸法の2枚は寸法が同じと判定される() {
    let 一枚目 = 圧縮前のHDR画像::テスト用に作る(2, 2, vec![0.0; 16]).unwrap();
    let 二枚目 = 圧縮前のHDR画像::テスト用に作る(2, 2, vec![1.0; 16]).unwrap();
    assert!(一枚目.寸法が同じか(&二枚目));
}

#[test]
fn 四の倍数のバイト列は成分へ開ける() {
    let 成分列 = 単精度へ開く(&[0u8; 8], 検査のパス()).unwrap();
    assert_eq!(成分列.len(), 2);
}

#[test]
fn 端数のバイトが残るバイト列は拒まれる() {
    for 端数 in 1..成分あたりのバイト数() {
        let バイト長 = 8 + 端数;
        let 結果 = 単精度へ開く(&vec![0u8; バイト長], 検査のパス());
        assert!(結果.is_err(), "{バイト長}バイト(端数{端数})が成分の境界で終わっているとして通った");
    }
}

/// 端数の検査が回す幅。1成分あたりのバイト数そのものである。
fn 成分あたりのバイト数() -> usize {
    4
}
