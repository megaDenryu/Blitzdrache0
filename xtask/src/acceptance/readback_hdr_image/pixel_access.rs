//! 圧縮前のHDR画像の画素の読み出し。触れるのは`成分列`と、その添字を組むための`幅`・`高さ`だけである。
//!
//! 成分の並べ方(RGBAの4成分を先頭から、行を上から順に)を知るのはこのファイルだけであり、
//! 判定側は番号だけで読む。並べ方の知識をここへ閉じるのは、書き出しの並びが変わったときに
//! 直す場所を1つにするためである。

use super::super::pixel_geometry::画素の番号;
use super::{圧縮前のHDR画像, 画素あたりの成分数};

impl 圧縮前のHDR画像 {
    /// 先頭から数えた画素のRGB。透過の成分は判定が1つも読まないため返さない。
    ///
    /// 注意: 画素数以上の番号を渡すことは呼び出し側のバグであるため、そのときは破れた不変条件を名指しして落とす。
    pub fn 番号の画素(&self, 番号: 画素の番号) -> [f32; 3] {
        assert!(
            番号.値() < self.画素数(),
            "圧縮前のHDR画像({}画素)の外の画素(番号{})を読もうとした",
            self.画素数(),
            番号.値()
        );
        let 先頭 = 番号.値() * 画素あたりの成分数;
        [self.成分列[先頭], self.成分列[先頭 + 1], self.成分列[先頭 + 2]]
    }

    /// 画素を4成分ずつ先頭から並べた並び。全画素を順に見る集計がこれを使う。
    pub fn 画素列(&self) -> impl Iterator<Item = &[f32]> {
        self.成分列.chunks_exact(画素あたりの成分数)
    }

    /// 先頭から数えた画素の番号の並び。2枚を同じ順で突き合わせる判定がこれを使う。
    pub fn 画素の番号一覧(&self) -> impl Iterator<Item = 画素の番号> {
        (0..self.画素数()).map(画素の番号::生成する)
    }
}
