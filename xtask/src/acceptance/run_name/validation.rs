//! 検収の実行名として受け入れる綴りの検査。2つの構築の口(実行時の`生成する`と原文の`定数から生成する`)が
//! どちらもここを通る。口ごとに検査を書くと、片方だけが緩い状態が生まれる。
//!
//! 拒む側でなく許す側を数え上げるのは、この綴りがWindowsのファイル名になるためである。禁止文字を並べる形は
//! 数え落としがそのまま穴になる。実際に既存の実行名はすべて英数字と下線であり、許可の集合はそこに収まる。
//!
//! 点を許さないのは、拡張子の付け替えが最後の点から後ろを置き換えるためである。`a.b`のような実行名は
//! `a.raw`と`a.size`へ化け、別の実行の書き出しを上書きしうる。
//!
//! 予約された装置の名前を拒むのは、Windowsがそれをファイルとして開けないためである。開けない綴りでも
//! 起動までは成功し、破れは書き出しの後の読み戻しで初めて出る。
//!
//! 検査を`const fn`で書くのは、原文のリテラルの破れをコンパイル時に落とすためである。

/// Windowsがファイル名として受け付けない装置の名前。大文字と小文字は区別されない。
const 予約された装置の名前: [&str; 22] = [
    "CON", "PRN", "AUX", "NUL", "COM1", "COM2", "COM3", "COM4", "COM5", "COM6", "COM7", "COM8", "COM9", "LPT1", "LPT2", "LPT3", "LPT4", "LPT5",
    "LPT6", "LPT7", "LPT8", "LPT9",
];

/// 実行名として破れうる前提。`const fn`から返して原文の検査に使うため、枝は値を持たない。
/// どの文字が破っているかは、文面を組む実行時の側が改めて探す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 実行名の破れ {
    空である,
    使えない文字を含む,
    予約された装置の名前である,
}

/// 実行名として使ってよい文字。英数字と下線とハイフンだけである。
pub(super) const fn 使ってよい文字か(文字: u8) -> bool {
    文字.is_ascii_alphanumeric() || 文字 == b'_' || 文字 == b'-'
}

/// 破れがあればそれを返す。無ければ値なしを返す。
pub(super) const fn 確かめる(綴り: &str) -> Option<実行名の破れ> {
    let バイト列 = 綴り.as_bytes();
    if バイト列.is_empty() {
        return Some(実行名の破れ::空である);
    }
    let mut 位置 = 0;
    while 位置 < バイト列.len() {
        if !使ってよい文字か(バイト列[位置]) {
            return Some(実行名の破れ::使えない文字を含む);
        }
        位置 += 1;
    }
    if 予約された装置の名前か(バイト列) {
        return Some(実行名の破れ::予約された装置の名前である);
    }
    None
}

const fn 予約された装置の名前か(綴り: &[u8]) -> bool {
    let mut 番号 = 0;
    while 番号 < 予約された装置の名前.len() {
        if 大文字小文字を無視して等しいか(綴り, 予約された装置の名前[番号].as_bytes()) {
            return true;
        }
        番号 += 1;
    }
    false
}

/// 注意: `eq_ignore_ascii_case`は定数評価で使えないため、大文字へ揃えて1バイトずつ比べる。
/// 原文のリテラルの破れをコンパイル時に落とすことが、この検査を`const fn`にしている理由である。
#[allow(clippy::manual_ignore_case_cmp)]
const fn 大文字小文字を無視して等しいか(左: &[u8], 右: &[u8]) -> bool {
    if 左.len() != 右.len() {
        return false;
    }
    let mut 位置 = 0;
    while 位置 < 左.len() {
        if 左[位置].to_ascii_uppercase() != 右[位置].to_ascii_uppercase() {
            return false;
        }
        位置 += 1;
    }
    true
}
