//! 検収の実行名の検証の回帰検査。呼ばれるのは`cargo test`だけである。
//!
//! 検証を置いた理由の裏返しを固定する。この綴りはWindowsのファイル名になるため、区切り・空白・
//! 禁止文字・予約された装置の名前のどれもが、起動までは成功して読み戻しで初めて破れる。
//!
//! 2つの構築の口が同じ判定であることも固定する。片方だけが緩いと、定数として書いた名前だけが
//! 検査をすり抜ける。原文の口はコンパイル時に落ちるため試験からは呼べないので、
//! 同じ判定関数を通っていることを`確かめる`の直呼びで見る。

#![allow(clippy::unwrap_used)]

use super::validation::{実行名の破れ, 確かめる};
use super::検収の実行名;

#[test]
fn 英数字と下線とハイフンの綴りは通る() {
    assert_eq!(検収の実行名::生成する("flat").unwrap().to_string(), "flat");
    assert_eq!(検収の実行名::生成する("night_x4_1").unwrap().to_string(), "night_x4_1");
    assert!(検収の実行名::生成する("contrast-bc1").is_ok(), "ハイフンを含む1語が拒まれた");
    assert!(検収の実行名::生成する("Helmet2").is_ok(), "大文字と数字を含む1語が拒まれた");
}

#[test]
fn 空の綴りは拒まれる() {
    assert_eq!(確かめる(""), Some(実行名の破れ::空である));
    assert!(検収の実行名::生成する("").is_err());
}

#[test]
fn 区切りを含む綴りは拒まれる() {
    for 綴り in ["外/flat", "外\\flat", "C:flat"] {
        assert!(検収の実行名::生成する(綴り).is_err(), "{綴り}が通った");
    }
}

#[test]
fn 空白と制御文字を含む綴りは拒まれる() {
    for 綴り in ["flat post", "flat\n", "flat\t", "flat\u{7}", "flat\u{0}", "flat\u{a0}", "flat\u{3000}"] {
        assert!(検収の実行名::生成する(綴り).is_err(), "{綴り:?}が通った");
    }
}

/// 点は拡張子の付け替えが読む区切りである。`a.b`は`a.raw`と`a.size`へ化け、別の実行の書き出しを上書きする。
#[test]
fn 点を含む綴りは拒まれる() {
    assert!(検収の実行名::生成する("flat.post").is_err(), "点を含む綴りが通った");
    assert!(検収の実行名::生成する("flat.").is_err(), "点で終わる綴りが通った");
}

#[test]
fn ファイル名に置けない記号を含む綴りは拒まれる() {
    for 綴り in ["flat?", "flat*", "flat\"", "flat<", "flat>", "flat|"] {
        assert!(検収の実行名::生成する(綴り).is_err(), "{綴り}が通った");
    }
}

#[test]
fn 予約された装置の名前は大文字小文字を問わず拒まれる() {
    for 綴り in ["CON", "con", "Nul", "aux", "COM1", "lpt9", "PRN"] {
        assert_eq!(
            確かめる(綴り),
            Some(実行名の破れ::予約された装置の名前である),
            "{綴り}が予約された装置の名前として拒まれない"
        );
        assert!(検収の実行名::生成する(綴り).is_err(), "{綴り}が通った");
    }
}

#[test]
fn 予約された装置の名前に似た綴りは通る() {
    for 綴り in ["console", "con1", "com0", "com10", "nul_mask"] {
        assert!(検収の実行名::生成する(綴り).is_ok(), "{綴り}が誤って拒まれた");
    }
}

/// ASCII以外はすべて拒む。許可する文字を数え上げる形にしているため、数え落としが穴にならない。
#[test]
fn ascii以外の文字を含む綴りは拒まれる() {
    for 綴り in ["対照の板", "flat対照", "ｆｌａｔ"] {
        assert!(検収の実行名::生成する(綴り).is_err(), "{綴り}が通った");
    }
}
