//! 検収の実行名の検証の回帰検査。呼ばれるのは`cargo test`だけである。
//!
//! 検証を置いた理由の裏返しを固定する。区切りを含む綴りは書き出し先を別のディレクトリへ曲げ、
//! 空白を含む綴りはコマンドの引数として1語にならない。どちらも起動までは成功し、
//! 破れは書き出しの後の読み戻しで初めて出るため、構築時に拒む。

#![allow(clippy::unwrap_used)]

use super::検収の実行名;

#[test]
fn 一語の綴りは通る() {
    assert_eq!(検収の実行名::生成する("flat").unwrap().to_string(), "flat");
    assert_eq!(検収の実行名::生成する("night_x4_1").unwrap().to_string(), "night_x4_1");
    assert!(検収の実行名::生成する("対照の板(全てRGBA8)").is_ok(), "日本語と括弧を含む1語が拒まれた");
}

#[test]
fn 空の綴りは拒まれる() {
    assert!(検収の実行名::生成する("").is_err());
}

#[test]
fn 区切りを含む綴りは拒まれる() {
    assert!(検収の実行名::生成する("外/flat").is_err(), "区切りを含む綴りが通った");
    assert!(検収の実行名::生成する("外\\flat").is_err(), "区切りを含む綴りが通った");
    assert!(検収の実行名::生成する("C:flat").is_err(), "ドライブの区切りを含む綴りが通った");
}

#[test]
fn 空白を含む綴りは拒まれる() {
    assert!(検収の実行名::生成する("flat post").is_err(), "空白を含む綴りが通った");
    assert!(検収の実行名::生成する("flat\n").is_err(), "改行を含む綴りが通った");
}

#[test]
fn 制御文字を含む綴りは拒まれる() {
    assert!(検収の実行名::生成する("flat\u{7}").is_err(), "制御文字を含む綴りが通った");
}
