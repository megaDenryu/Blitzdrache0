//! 使えない文字の誤りが、実際に破っている文字を名指すことの回帰検査。呼ばれるのは`cargo test`だけである。
//!
//! この検査を分けて置くのは、見るものが「拒むかどうか」ではなく「誤りの文面が指す文字が正しいか」だからである。
//! バイトで探す実装は、ASCII以外の文字のUTF-8の先頭バイトを別の文字へ写して報告していた(`対`が`å`になった)。
//! 拒む側の検査は全部通ったままこの破れが残るため、別の検査が要る。

#![allow(clippy::expect_used)]

use super::検収の実行名;
use crate::acceptance::検収エラー;

/// 誤りの文面が名指す文字が、実際に破っている文字であることを固定する。
///
/// バイトで探す実装は、ASCII以外の文字のUTF-8の先頭バイトを別の文字へ写して報告していた
/// (`対`が`å`になった)。文字で走査していればこの検査が通る。
#[test]
fn 使えない文字の誤りは実際の文字を名指す() {
    for (綴り, 期待する文字) in [("対照", '対'), ("flat対照", '対'), ("ｆｌａｔ", 'ｆ'), ("flat post", ' '), ("a.b", '.')] {
        let 誤り = 検収の実行名::生成する(綴り).expect_err("使えない文字を含む綴りが通った");
        match 誤り {
            検収エラー::検収の実行名が使えない文字を含む { 文字, 名前 } => {
                assert_eq!(文字, 期待する文字, "{綴り}が名指した文字が違う");
                assert_eq!(名前, 綴り);
            }
            その他 => panic!("{綴り}が使えない文字の誤りにならない: {その他}"),
        }
    }
}
