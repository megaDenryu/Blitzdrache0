//! アプリの起動: 1回ぶんのプロセス起動を、引数を積んでから走らせるまで持つセッション型。
//!
//! 起こす手順をコールバックで挟まずこの型で表すのは、積む・走らせる・終了状態を判定するの3手が
//! その場で1回ずつ実行される括りであるためである。積み終える前に走らせる形は、この型を通す限り書けない。
//!
//! 引数を積む口を用途ごとに分けるのは、綴り(`--asset-root`等)をこの型の中だけに置くためである。
//! 汎用の「引数を足す」だけを出すと、同じ綴りが呼び出し側の数だけ書かれる。
//!
//! 始める口が`完成した起動引数`だけを受けるのは、予約された選択肢の検証をセッションを始める前に
//! 済ませるためである。セッションの中で落とすと、未終了のセッションが破棄されて閉じ忘れのpanicが
//! 型付きエラーを隠す。
//!
//! 閉じ忘れの検出を`#[must_use]`だけに頼らないのは、変数へ受けて引数を積んだ後に終端メソッドを呼ばず
//! スコープを抜ける形が、その注記では捕まらないためである。終端メソッドだけが終了済みへ遷移し、
//! 未終了のまま捨てられたら破れた不変条件を名指しして落とす。走らせて終わらせる局面は`terminate`が、
//! 破棄の検出は`drop_guard`が持つ。

mod drop_guard;
#[cfg(test)]
mod drop_tests;
mod terminate;

use std::process::Command;

use super::app_executable::アプリの起こし方;
use super::dump_format::書き出しの形式;
use super::launch_arguments::完成した起動引数;
use super::readback_dump::読み戻しの書き出し先;
use super::run_name::検収の実行名;
use super::runtime_asset_root::実行時アセットルート;

/// 読む世界の置き場をアプリへ渡す選択肢の綴り。生の綴りが在るのはこの1行だけである。
pub(super) const 読む世界の置き場の選択肢の綴り: &str = "--asset-root";

#[must_use]
pub(super) struct アプリの起動 {
    起こし方: アプリの起こし方,
    実行名: 検収の実行名,
    コマンド: Command,
    /// 終端メソッドを通ったか。`Drop`がこれを見て閉じ忘れを落とす。
    終了済みか: bool,
}

impl アプリの起動 {
    /// 検証済みの引数列だけを受けて始まる。検証していない指定でセッションを作る形は、この口を通す限り書けない。
    pub(super) fn 始める(起こし方: アプリの起こし方, 実行名: 検収の実行名, 引数: &完成した起動引数) -> Self {
        let mut コマンド = 起こし方.コマンドを作る();
        引数.コマンドへ並べる(&mut コマンド);
        Self {
            起こし方,
            実行名,
            コマンド,
            終了済みか: false,
        }
    }

    pub(super) fn 読む世界の置き場を積む(&mut self, アセットルート: &実行時アセットルート) {
        self.コマンド
            .arg(読む世界の置き場の選択肢の綴り)
            .arg(アセットルート.起動引数として渡す綴り());
    }

    /// 最終フレームを指定の形式で書き出させる。
    pub(super) fn 書き出し先を積む(&mut self, 書き出し先: &読み戻しの書き出し先, 形式: 書き出しの形式) {
        self.コマンド.arg(形式.選択肢の綴り()).arg(書き出し先.起動引数として渡す綴り());
    }
}
