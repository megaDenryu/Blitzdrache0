//! 読み戻し画像の不変条件と、寸法の本文の解き方の回帰検査。呼ばれるのは`cargo test`だけである。
//!
//! 不変条件の検査をここへ置くのは、破れた値が作れると「範囲内の座標を渡したのに範囲外を読む」状態が
//! 成立するためである。寸法の解き方の検査を並べて置くのは、数として読めない語を捨てる実装が
//! 壊れた書き出しを正しい寸法として通してしまい、その破れが同じ型の構築に現れるためである。

#![allow(clippy::unwrap_used)]

use super::load::幅と高さの2数を解く;
use super::読み戻し画像;

/// 幅2・高さ1の絵ちょうどのバイト列。RGBA8であるため1画素あたり4バイトである。
fn 二画素ぶんのバイト列() -> Vec<u8> {
    vec![0u8; 8]
}

#[test]
fn 寸法とバイト長が合う構築は通る() {
    let 画像 = 読み戻し画像::テスト用に作る(2, 1, 二画素ぶんのバイト列()).unwrap();
    assert_eq!(画像.幅(), 2);
    assert_eq!(画像.高さ(), 1);
    assert_eq!(画像.画素数(), 2);
}

#[test]
fn バイト列が短い構築は拒まれる() {
    let 結果 = 読み戻し画像::テスト用に作る(2, 1, vec![0u8; 4]);
    assert!(結果.is_err(), "1画素ぶんしかないバイト列が2画素の絵として通った");
}

#[test]
fn バイト列が長い構築は拒まれる() {
    let 結果 = 読み戻し画像::テスト用に作る(2, 1, vec![0u8; 12]);
    assert!(結果.is_err(), "3画素ぶんのバイト列が2画素の絵として通った");
}

#[test]
fn 寸法がバイト長へ収まらない構築は拒まれる() {
    let 結果 = 読み戻し画像::テスト用に作る(usize::MAX, 2, Vec::new());
    assert!(結果.is_err(), "掛け算が溢れる寸法が通った");
}

#[test]
fn 幅と高さの2数だけが解ける() {
    assert_eq!(幅と高さの2数を解く("1920 1080"), Some((1920, 1080)));
    assert_eq!(幅と高さの2数を解く(" 1920\n1080\n"), Some((1920, 1080)));
}

#[test]
fn 数として読めない語を挟んだ寸法は拒まれる() {
    assert_eq!(幅と高さの2数を解く("1920 壊れた語 1080"), None, "数でない語を捨てて2数として通った");
    assert_eq!(幅と高さの2数を解く("1920 1080 720"), None, "3数が2数として通った");
    assert_eq!(幅と高さの2数を解く("1920"), None);
    assert_eq!(幅と高さの2数を解く(""), None);
    assert_eq!(幅と高さの2数を解く("-1 1080"), None, "負の数が通った");
}
