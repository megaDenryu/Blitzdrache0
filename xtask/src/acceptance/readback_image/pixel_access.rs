//! 読み戻し画像の画素の読み出し。触れるのは`rgba8`と、その添字を組むための`幅`・`高さ`だけである。
//!
//! バイト列の並べ方(RGBA8を先頭から4バイトずつ、行を上から順に)を知るのはこのファイルだけであり、
//! 判定側は座標か番号だけで読む。並べ方の知識をここへ閉じるのは、書き出しの並びが変わったときに
//! 直す場所を1つにするためである。
//!
//! 注意: どの口も範囲の検査を持つ。範囲外の読み出しは呼び出し側のバグであり、
//! 型の不変条件(バイト長=幅×高さ×4)が保たれている限り、範囲内なら必ず読める。

use super::super::pixel_geometry::{画素の横位置, 画素の番号, 画素の縦位置};
use super::{画素あたりのバイト数, 読み戻し画像};

impl 読み戻し画像 {
    /// 位置の画素のRGB。
    ///
    /// 注意: 範囲外の座標を渡すことは呼び出し側のバグであるため、そのときは破れた不変条件を名指しして落とす。
    pub fn 座標の画素(&self, 横: 画素の横位置, 縦: 画素の縦位置) -> [u8; 3] {
        assert!(
            横.値() < self.幅.画素数() && 縦.値() < self.高さ.画素数(),
            "読み戻し画像({}×{})の外の画素({}, {})を読もうとした",
            self.幅.画素数(),
            self.高さ.画素数(),
            横.値(),
            縦.値()
        );
        self.番号の画素(画素の番号::生成する(縦.値() * self.幅.画素数() + 横.値()))
    }

    /// 先頭から数えた画素のRGB。走査の順序だけが要る判定は座標を組み立てずにこちらで読む。
    ///
    /// 注意: 画素数以上の番号を渡すことは呼び出し側のバグであるため、そのときは破れた不変条件を名指しして落とす。
    pub fn 番号の画素(&self, 番号: 画素の番号) -> [u8; 3] {
        assert!(
            番号.値() < self.画素数(),
            "読み戻し画像({}画素)の外の画素(番号{})を読もうとした",
            self.画素数(),
            番号.値()
        );
        let 先頭 = 番号.値() * 画素あたりのバイト数;
        [self.rgba8[先頭], self.rgba8[先頭 + 1], self.rgba8[先頭 + 2]]
    }

    /// 画素を4バイトずつ先頭から並べた並び。全画素を順に見る判定がこれを使う。
    pub fn 画素列(&self) -> impl Iterator<Item = &[u8]> {
        self.rgba8.chunks_exact(画素あたりのバイト数)
    }

    /// RGBA8の連結そのもの。2枚のバイト一致を見る判定と、書き出しへ渡す境界だけが読む。
    pub fn バイト列(&self) -> &[u8] {
        &self.rgba8
    }

    /// その行の先頭から末尾までのバイト列。画面を上下に切って片側だけのバイト一致を見る判定が読む。
    ///
    /// 注意: 高さ以上の行を渡すことは呼び出し側のバグであるため、そのときは破れた不変条件を名指しして落とす。
    pub fn 行以降のバイト列(&self, 縦: 画素の縦位置) -> &[u8] {
        assert!(
            縦.値() <= self.高さ.画素数(),
            "読み戻し画像(高さ{})の外の行{}を読もうとした",
            self.高さ.画素数(),
            縦.値()
        );
        &self.rgba8[縦.値() * self.幅.画素数() * 画素あたりのバイト数..]
    }
}
