//! 読み戻し画像のテスト専用構築。呼ばれるのは`cargo test`だけであり、本番の`読み込む`(書き出されたファイルを
//! 読む)とは呼び出しタイミングが明確に異なるため、生成の局面をここへ分ける。

use super::読み戻し画像;

impl 読み戻し画像 {
    /// 合成したRGBA8バイト列から作る。判定のユニットテストが、実機を起動せずに既知の画素配置を持つ絵を
    /// 用意するために使う。
    ///
    /// 注意: 寸法とバイト長が合っていることはこの口では確かめない。合わない値を渡すのは試験の書き誤りであり、
    /// 範囲外を読んだ時点で画素の読み出しが落ちる。
    pub fn テスト用に作る(幅: usize, 高さ: usize, rgba8: Vec<u8>) -> Self {
        Self { 幅, 高さ, rgba8 }
    }
}
