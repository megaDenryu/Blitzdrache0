//! 書き出された対の2ファイルを1つの読み戻し画像へ写す工程。受け取るのは書き出し先、返すのは読み戻し画像である。
//! 担当するのは、寸法のファイルを2つの数として読むことと、バイト長が寸法と合っていることを確かめることだけである。

use std::path::PathBuf;

use super::super::error::検収エラー;
use super::super::readback_dump::読み戻しの書き出し先;
use super::読み戻し画像;

/// 1画素あたりのバイト数。書き出しはRGBA8の連結であり、寸法からバイト長を求めるのにこの数を掛ける。
const 画素あたりのバイト数: usize = 4;

pub(super) fn 対の2ファイルから読み込む(書き出し先: &読み戻しの書き出し先) -> Result<読み戻し画像, 検収エラー> {
    let (幅, 高さ) = 寸法を読む(書き出し先)?;
    let 画素のパス = 書き出し先.画素のパス();
    let rgba8 = std::fs::read(&画素のパス).map_err(|誤り| 検収エラー::読み戻しのファイルを読めない {
        パス: 画素のパス, 誤り
    })?;
    let 寸法から求めたバイト長 = 幅
        .checked_mul(高さ)
        .and_then(|画素数| 画素数.checked_mul(画素あたりのバイト数))
        .ok_or(検収エラー::読み戻しの寸法がバイト長へ収まらない { 幅, 高さ })?;
    if rgba8.len() != 寸法から求めたバイト長 {
        return Err(検収エラー::読み戻しの寸法とバイト長が食い違う {
            寸法から求めたバイト長,
            実際のバイト長: rgba8.len(),
        });
    }
    Ok(読み戻し画像 { 幅, 高さ, rgba8 })
}

/// 寸法のファイルは「幅 高さ」の2数だけを持つ。2数として読めなければ、その中身を添えて落とす。
fn 寸法を読む(書き出し先: &読み戻しの書き出し先) -> Result<(usize, usize), 検収エラー> {
    let 寸法のパス: PathBuf = 書き出し先.寸法のパス();
    let 本文 = std::fs::read_to_string(&寸法のパス).map_err(|誤り| 検収エラー::読み戻しのファイルを読めない {
        パス: 寸法のパス.clone(),
        誤り,
    })?;
    let 数一覧: Vec<usize> = 本文.split_whitespace().filter_map(|語| 語.parse().ok()).collect();
    let [幅, 高さ] = 数一覧[..] else {
        return Err(検収エラー::読み戻しの寸法が幅と高さの2数でない {
            パス: 寸法のパス, 本文
        });
    };
    Ok((幅, 高さ))
}
