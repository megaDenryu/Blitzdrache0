//! 書き出された対の2ファイルを1つの読み戻し画像へ写す工程。受け取るのは書き出し先、返すのは読み戻し画像である。
//! 担当するのは、対の2ファイルを読んで寸法の本文を「幅 高さ」の2数として解くことだけである。
//! バイト長が寸法と合っていることの確認は、この型の不変条件として`読み戻し画像`の構築の口が持つ。

use std::path::PathBuf;

use super::super::error::検収エラー;
use super::super::readback_dump::読み戻しの書き出し先;
use super::読み戻し画像;

pub(super) fn 対の2ファイルから読み込む(書き出し先: &読み戻しの書き出し先) -> Result<読み戻し画像, 検収エラー> {
    let (幅, 高さ) = 寸法を読む(書き出し先)?;
    let 画素のパス = 書き出し先.画素のパス();
    let rgba8 = std::fs::read(&画素のパス).map_err(|誤り| 検収エラー::読み戻しのファイルを読めない {
        パス: 画素のパス, 誤り
    })?;
    読み戻し画像::検証して組み立てる(幅, 高さ, rgba8)
}

/// 寸法のファイルは「幅 高さ」の2数だけを持つ。
///
/// 注意: 数として読めない語を捨ててはならない。捨てると「1920 壊れた語 1080」が1920×1080として通り、
/// 書き出しが壊れた実行の絵をそのまま判定してしまう。語は1つ残らず数として読み、ちょうど2語であることを求める。
fn 寸法を読む(書き出し先: &読み戻しの書き出し先) -> Result<(usize, usize), 検収エラー> {
    let 寸法のパス: PathBuf = 書き出し先.寸法のパス();
    let 本文 = std::fs::read_to_string(&寸法のパス).map_err(|誤り| 検収エラー::読み戻しのファイルを読めない {
        パス: 寸法のパス.clone(),
        誤り,
    })?;
    幅と高さの2数を解く(&本文).ok_or(検収エラー::読み戻しの寸法が幅と高さの2数でない {
        パス: 寸法のパス, 本文
    })
}

/// 本文を空白で区切り、ちょうど2語がどちらも数であるときだけ幅と高さを返す。
pub(super) fn 幅と高さの2数を解く(本文: &str) -> Option<(usize, usize)> {
    let 数一覧 = 本文.split_whitespace().map(str::parse::<usize>).collect::<Result<Vec<usize>, _>>().ok()?;
    match 数一覧[..] {
        [幅, 高さ] => Some((幅, 高さ)),
        _ => None,
    }
}
