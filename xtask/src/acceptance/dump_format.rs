//! 書き出しの形式: 最終フレームをどの形式で書き出させるか。明るさの圧縮とsRGB符号化を通した提示画像と、
//! 通す前の単精度である。
//!
//! 真偽値で持たないのは、真がどちらを指すかが呼び出し側の記憶になるためである。
//! アプリへ渡す選択肢の綴りを知るのはこの型だけであり、書き出しを求める入口はどれも枝の名前で指定する。

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum 書き出しの形式 {
    /// 明るさの圧縮とsRGB符号化を通したRGBA8。絵の目視と画素の判定がこれを読む。
    提示画像,
    /// 明るさの圧縮を通す前の単精度。項ごとの比や輝度の分布を測る判定がこれを読む。
    明るさの圧縮前,
    /// 深度プリパスが書いた最終深度。深度の同値性を見る判定がこれを読む。
    最終深度,
}

impl 書き出しの形式 {
    pub(super) fn 選択肢の綴り(self) -> &'static str {
        match self {
            Self::提示画像 => "--dump-frame",
            Self::明るさの圧縮前 => "--dump-hdr-frame",
            Self::最終深度 => "--dump-depth-frame",
        }
    }

    /// その形式で書き出されたファイルの拡張子。綴りを知るのはこの型だけである。
    pub(super) fn 拡張子(self) -> &'static str {
        match self {
            Self::提示画像 => "raw",
            Self::明るさの圧縮前 => "hdr32",
            Self::最終深度 => "depth32",
        }
    }
}
