//! 大小を課す3つの口が、非数と両向きの無限大を1つも通さないことの反証。
//!
//! この検査が要るのは、非数だけを`partial_cmp`の`None`で落とす形が無限大を漏らすためである。
//! 無限大は順序を持つため、負の無限大はどんな上限も下回って合格し、正の無限大はどんな下限も上回って合格する。
//! 有限性の関門を外すとこの検査が落ちる。

#![allow(clippy::unwrap_used)]

use crate::acceptance::判定の名前;

const 判定名: 判定の名前 = 判定の名前::定数から生成する("有限性の反証");

/// 非数と両向きの無限大。大小を課す口はどれも通してはならない。
const 有限でない実測一覧: [f64; 3] = [f64::NAN, f64::INFINITY, f64::NEG_INFINITY];

#[test]
fn 上限を課す口は有限でない実測を1つも通さない() {
    for 実測 in 有限でない実測一覧 {
        let 誤り = 判定名.上限を課す(実測, 1.0).unwrap_err().to_string();
        assert!(誤り.contains("有限でない"), "実測{実測}が上限を素通りした: {誤り}");
    }
}

#[test]
fn 下限を課す口は有限でない実測を1つも通さない() {
    for 実測 in 有限でない実測一覧 {
        let 誤り = 判定名.下限を課す(実測, 1.0).unwrap_err().to_string();
        assert!(誤り.contains("有限でない"), "実測{実測}が下限を素通りした: {誤り}");
    }
}

#[test]
fn 許容の範囲を課す口は有限でない実測を1つも通さない() {
    for 実測 in 有限でない実測一覧 {
        let 誤り = 判定名.許容の範囲を課す(実測, 0.0, 1.0).unwrap_err().to_string();
        assert!(誤り.contains("有限でない"), "実測{実測}が許容の範囲を素通りした: {誤り}");
    }
}

/// 無限大が漏れる向きを名指しで固定する。負の無限大は上限の比べで、正の無限大は下限の比べで、
/// どちらも順序を持つがゆえに合格していた。
#[test]
fn 無限大は漏れる向きでも落ちる() {
    assert!(判定名.上限を課す(f64::NEG_INFINITY, 1.0).is_err(), "負の無限大が上限を下回って合格した");
    assert!(判定名.下限を課す(f64::INFINITY, 1.0).is_err(), "正の無限大が下限を上回って合格した");
}

/// 有限の実測は今までどおり通る。境界の等号も保つ。
#[test]
fn 有限の実測は境界の等号まで通る() {
    assert!(判定名.上限を課す(1.0, 1.0).is_ok(), "上限ちょうどが落ちた");
    assert!(判定名.下限を課す(1.0, 1.0).is_ok(), "下限ちょうどが落ちた");
    assert!(判定名.許容の範囲を課す(0.0, 0.0, 1.0).is_ok(), "下端ちょうどが落ちた");
    assert!(判定名.許容の範囲を課す(1.0, 0.0, 1.0).is_ok(), "上端ちょうどが落ちた");
    assert!(判定名.上限を課す(1.5, 1.0).is_err(), "上限を超えた実測が通った");
    assert!(判定名.下限を課す(0.5, 1.0).is_err(), "下限に届かない実測が通った");
}

/// 整数の型は常に有限であり、関門を通っても判定が変わらない。
#[test]
fn 整数の判定は関門で変わらない() {
    assert!(判定名.上限を課す(3_u64, 3).is_ok());
    assert!(判定名.上限を課す(4_u64, 3).is_err());
    assert!(判定名.下限を課す(3_usize, 3).is_ok());
    assert!(判定名.許容の範囲を課す(2_u32, 1, 3).is_ok());
}
