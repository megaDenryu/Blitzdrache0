//! 判定の名前が課す、値が等しいことの比べ。触れるのは名前だけである。
//!
//! 数と綴りで口を分けるのは、綴りが大小を持たず写しの費用も違うためである。数は写しの費用が無いため値で受け、
//! 綴りは借りて受けて破れになるときだけ写す。数直線上の位置の比べは`order_imposition`が持つ。

use super::判定の名前;
use crate::acceptance::error::{判定の破れ, 判定の破れの種類};
use crate::acceptance::judgment_value::{判定が比べる値, 判定で比べられる値};

impl 判定の名前 {
    /// 実測が期待と等しいことを課す。
    pub fn 一致を課す<値: 判定で比べられる値>(&self, 実測: 値, 期待: 値) -> Result<(), 判定の破れ> {
        if 実測 == 期待 {
            return Ok(());
        }
        Err(self.破れを組む(判定の破れの種類::一致するはずが食い違った {
            実測: 実測.判定が比べる値へ写す(),
            期待: 期待.判定が比べる値へ写す(),
        }))
    }

    /// 実測の綴りが期待の綴りと等しいことを課す。行の綴りや段の表示のように大小を持たない値がこの口を通る。
    pub fn 綴りの一致を課す(&self, 実測: &str, 期待: &str) -> Result<(), 判定の破れ> {
        if 実測 == 期待 {
            return Ok(());
        }
        Err(self.破れを組む(判定の破れの種類::一致するはずが食い違った {
            実測: 判定が比べる値::綴り(実測.to_string()),
            期待: 判定が比べる値::綴り(期待.to_string()),
        }))
    }

    /// 報告が真偽で答えた一致が真であることを課す。何と何が一致したかは名前が言う。
    pub fn 真であることを課す(&self, 実測: bool) -> Result<(), 判定の破れ> {
        if 実測 {
            return Ok(());
        }
        self.綴りの一致を課す("偽", "真")
    }

    /// 件数が零であることを課す。
    pub fn 零件であることを課す<値: 判定で比べられる値>(&self, 件数: 値) -> Result<(), 判定の破れ> {
        if 件数 == 値::零 {
            return Ok(());
        }
        Err(self.破れを組む(判定の破れの種類::零件のはずが残った {
            件数: 件数.判定が比べる値へ写す(),
        }))
    }
}
