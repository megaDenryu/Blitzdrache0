//! 判定の名前が課す、値が数直線のどこに在るかの比べ。触れるのは名前だけであり、
//! 実測と期待のどちらを左に置くかを決める唯一の場所である。
//!
//! 比べを呼び出し側の`if`に委ねると、上限と下限を取り違えた形が書けてしまう。実測では同じ「上限を超えた」が
//! 入口ごとの文面で書かれており、どちらの数が実測なのかは文面を読まないと分からなかった。
//!
//! 有限であることと正であることをここへ置くのは、どちらも数直線上での位置の話であり、
//! 大小の比べが素通りしてしまう値(非数・無限大・零の分母)をその手前で落とすためである。
//! 等しさの比べは`equality_imposition`が持つ。
//!
//! 注意: 大小を課す3つの口は、比べる前に実測が有限であることを必ず確かめる。非数だけを`partial_cmp`の
//! `None`で落とす形では無限大が漏れる。無限大は順序を持つため、負の無限大がどんな上限も下回り、
//! 正の無限大がどんな下限も上回って合格する。無限大が漏れないことの反証は`finiteness_tests`が持つ。

#[cfg(test)]
mod finiteness_tests;

use super::判定の名前;
use crate::acceptance::error::{判定の破れ, 判定の破れの種類};
use crate::acceptance::judgment_value::判定で比べられる値;

impl 判定の名前 {
    /// 実測が上限以下であることを課す。
    pub fn 上限を課す<値: 判定で比べられる値>(&self, 実測: 値, 上限: 値) -> Result<(), 判定の破れ> {
        self.比べられる実測であることを確かめる(実測)?;
        match 実測.partial_cmp(&上限) {
            None => Err(self.有限でない破れを組む(実測)),
            Some(順序) if 順序.is_gt() => Err(self.破れを組む(判定の破れの種類::上限を超えた {
                実測: 実測.判定が比べる値へ写す(),
                上限: 上限.判定が比べる値へ写す(),
            })),
            Some(_) => Ok(()),
        }
    }

    /// 実測が下限以上であることを課す。
    pub fn 下限を課す<値: 判定で比べられる値>(&self, 実測: 値, 下限: 値) -> Result<(), 判定の破れ> {
        self.比べられる実測であることを確かめる(実測)?;
        match 実測.partial_cmp(&下限) {
            None => Err(self.有限でない破れを組む(実測)),
            Some(順序) if 順序.is_lt() => Err(self.破れを組む(判定の破れの種類::下限に届かない {
                実測: 実測.判定が比べる値へ写す(),
                下限: 下限.判定が比べる値へ写す(),
            })),
            Some(_) => Ok(()),
        }
    }

    /// 実測が下限以上かつ上限以下であることを課す。片側だけの破れも同じ枝で返し、両端を文面へ出す。
    pub fn 許容の範囲を課す<値: 判定で比べられる値>(&self, 実測: 値, 下限: 値, 上限: 値) -> Result<(), 判定の破れ> {
        self.比べられる実測であることを確かめる(実測)?;
        let (Some(下との順序), Some(上との順序)) = (実測.partial_cmp(&下限), 実測.partial_cmp(&上限)) else {
            return Err(self.有限でない破れを組む(実測));
        };
        if 下との順序.is_lt() || 上との順序.is_gt() {
            return Err(self.破れを組む(判定の破れの種類::許容の範囲を外れた {
                実測: 実測.判定が比べる値へ写す(),
                下限: 下限.判定が比べる値へ写す(),
                上限: 上限.判定が比べる値へ写す(),
            }));
        }
        Ok(())
    }

    /// 実測が有限であることを課す。比の材料や統計の入力になる実数がこの口を通る。
    pub fn 有限であることを課す(&self, 実測: f64) -> Result<(), 判定の破れ> {
        self.比べられる実測であることを確かめる(実測)
    }

    /// 実測が正であることを課す。零を分母に置いた比は無限大になり、上限にも下限にも収まらない。
    pub fn 正であることを課す(&self, 実測: f64) -> Result<(), 判定の破れ> {
        if 実測 > 0.0 {
            return Ok(());
        }
        Err(self.破れを組む(判定の破れの種類::正でない {
            実測: 実測.判定が比べる値へ写す(),
        }))
    }

    /// 大小を課す口が比べの手前で通す関門。整数の型は常に有限であるため、この関門は何もしない。
    fn 比べられる実測であることを確かめる<値: 判定で比べられる値>(&self, 実測: 値) -> Result<(), 判定の破れ> {
        if 実測.有限か() {
            return Ok(());
        }
        Err(self.有限でない破れを組む(実測))
    }

    fn 有限でない破れを組む<値: 判定で比べられる値>(&self, 実測: 値) -> 判定の破れ {
        self.破れを組む(判定の破れの種類::有限でない {
            実測: 実測.判定が比べる値へ写す(),
        })
    }
}
