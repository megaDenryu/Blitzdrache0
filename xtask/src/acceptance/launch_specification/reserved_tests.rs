//! 汎用の口が型の組み立てる選択肢を拒むことの反証。呼ばれるのは`cargo test`だけである。
//!
//! これが要るのは、汎用の口から`--scene`や`--frames`を積めると、型で固定したシーンや正のフレーム数や
//! 書き出し先を後から上書き・重複できるためである。値オブジェクトが不変条件を守っても、
//! 同じ選択肢を重ねられるなら守れていない。

#![allow(clippy::unwrap_used)]

use std::path::Path;

use super::アプリの起動指定;
use crate::acceptance::{描画フレーム数, 検収シーン名};

const 検査のシーン: 検収シーン名 = 検収シーン名::生成する("quad");
const 検査の枚数: 描画フレーム数 = 描画フレーム数::生成する(1);

fn 指定を始める() -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(検査のシーン, 検査の枚数)
}

fn 並べてみる(指定: &アプリの起動指定) -> Result<(), crate::acceptance::検収エラー> {
    指定.引数列へ写す().map(|_| ())
}

#[test]
fn 予約されていない選択肢は通る() {
    let 指定 = 指定を始める().選択肢を足す("--no-taa").値を持つ選択肢を足す("--time-of-day", "43200");
    assert!(並べてみる(&指定).is_ok());
}

#[test]
fn シーンを汎用の口から積むと落ちる() {
    let 指定 = 指定を始める().値を持つ選択肢を足す("--scene", "terrain_origin");
    assert!(並べてみる(&指定).is_err(), "型が組み立てるシーンを汎用の口から上書きできた");
}

#[test]
fn 枚数を汎用の口から積むと落ちる() {
    for 綴り in ["--frames", "--benchmark-frames"] {
        let 指定 = 指定を始める().値を持つ選択肢を足す(綴り, "0");
        assert!(並べてみる(&指定).is_err(), "型が組み立てる{綴り}を汎用の口から上書きできた");
    }
}

#[test]
fn 世界の置き場と書き出し先を汎用の口から積むと落ちる() {
    for 綴り in ["--asset-root", "--dump-frame", "--dump-hdr-frame", "--dump-depth-frame"] {
        let 指定 = 指定を始める().パスを値に持つ選択肢を足す(綴り, Path::new("target/test"));
        assert!(並べてみる(&指定).is_err(), "型が組み立てる{綴り}を汎用の口から上書きできた");
    }
}

#[test]
fn まとめて足す口も予約された選択肢を拒む() {
    let 指定 = 指定を始める().選択肢をまとめて足す(&["--no-post", "--frames", "0"]);
    assert!(並べてみる(&指定).is_err(), "まとめて足す口から枚数を上書きできた");
}

/// 失敗の文面が「何が予約されているか」を並べることを見る。読み手が次に何を直せばよいか決められるためである。
#[test]
fn 失敗の文面は予約の一覧を並べる() {
    let 指定 = 指定を始める().選択肢を足す("--scene");
    let 文面 = 並べてみる(&指定).unwrap_err().to_string();
    for 綴り in [
        "--scene",
        "--frames",
        "--benchmark-frames",
        "--asset-root",
        "--dump-frame",
        "--dump-hdr-frame",
        "--dump-depth-frame",
    ] {
        assert!(文面.contains(綴り), "失敗の文面に{綴り}が無い: {文面}");
    }
}
