//! 実行時アセットルート: アプリが読む実行時形式一式の置き場を表す型。
//!
//! 出力ディレクトリや書き出し先と同じ`Path`で持つと、取り違えても型が通る。役割ごとに型を分ける。
//! 世界ごとに置き場が分かれるのは、1つの置き場が1つのカタログと1つのチャンク目録しか持てないためである
//! (綴りの正本は`compile_assets`の既定出力ルートが持つ)。

use std::path::{Path, PathBuf};

#[repr(transparent)]
pub struct 実行時アセットルート(PathBuf);

impl 実行時アセットルート {
    /// 綴りから作る。世界ごとの既定出力ルートを定数で持つ入口がこの口を通る。
    pub fn 綴りから生成する(綴り: &str) -> Self {
        Self(PathBuf::from(綴り))
    }

    /// 実行のたびに組み立てるパスから作る。焼き付け先を条件ごとに決める入口がこの口を通る。
    pub fn パスから生成する(パス: PathBuf) -> Self {
        Self(パス)
    }

    /// アプリの`--asset-root`へ渡す綴り。プロセス境界へ生のパスが出る唯一の場所である。
    pub(super) fn 起動引数として渡す綴り(&self) -> &Path {
        &self.0
    }
}
