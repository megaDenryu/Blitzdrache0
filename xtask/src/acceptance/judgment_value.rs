//! 判定が比べる値: 検収の判定が実測と期待の両側へ置く値。件数と実数と綴りの3種を数え上げる。
//!
//! 破れの型が実測と期待を文へ焼いてから持つと、「上限{下限}を超えた」のような役割の取り違えが文面にしか現れず、
//! 読み手はどちらの数が実測なのかを復元できない。値を型のまま持ち、文へ写すのは`Display`の1箇所だけにする。
//!
//! 大小を比べる操作をトレイトで受けるのは、件数と実数を1つのメソッドで扱いながら件数を実数へ写さないためである。
//! u64をf64へ写すと2^53を超える件数で桁が落ち、判定が実測どおりでなくなる。

use std::fmt;

#[derive(Debug, Clone, PartialEq)]
pub enum 判定が比べる値 {
    件数(u64),
    実数(f64),
    綴り(String),
}

impl fmt::Display for 判定が比べる値 {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::件数(値) => write!(書き手, "{値}"),
            Self::実数(値) => write!(書き手, "{値}"),
            Self::綴り(値) => write!(書き手, "{値}"),
        }
    }
}

/// 判定の大小比べに置ける値。比べは実装した型自身の順序で行い、写すのは文面へ出すときだけである。
///
/// 注意: `usize`の写しは`u64`へ収まらない値を`u64::MAX`で止める。比べは`usize`のまま行うため判定は実測どおりであり、
/// 止まるのは文面へ出る数だけである。64ビットの環境では収まらない値そのものが存在しない。
pub trait 判定で比べられる値: PartialOrd + Copy {
    /// 「零件である」「1件も無い」を課す判定が比べる原点。
    const 零: Self;

    fn 判定が比べる値へ写す(self) -> 判定が比べる値;
}

impl 判定で比べられる値 for u8 {
    const 零: Self = 0;

    fn 判定が比べる値へ写す(self) -> 判定が比べる値 {
        判定が比べる値::件数(u64::from(self))
    }
}

impl 判定で比べられる値 for u32 {
    const 零: Self = 0;

    fn 判定が比べる値へ写す(self) -> 判定が比べる値 {
        判定が比べる値::件数(u64::from(self))
    }
}

impl 判定で比べられる値 for u64 {
    const 零: Self = 0;

    fn 判定が比べる値へ写す(self) -> 判定が比べる値 {
        判定が比べる値::件数(self)
    }
}

impl 判定で比べられる値 for usize {
    const 零: Self = 0;

    fn 判定が比べる値へ写す(self) -> 判定が比べる値 {
        判定が比べる値::件数(u64::try_from(self).unwrap_or(u64::MAX))
    }
}

impl 判定で比べられる値 for f64 {
    const 零: Self = 0.0;

    fn 判定が比べる値へ写す(self) -> 判定が比べる値 {
        判定が比べる値::実数(self)
    }
}
