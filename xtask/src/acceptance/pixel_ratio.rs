//! 画素の占める割合: 画素の数どうしの比。物体が画面に占める広さや、囲む矩形が辺に占める長さがこれである。
//!
//! 割合を裸の`f64`で求めると、分母が零の実行が無限大を返し、その無限大が上限にも下限にも収まらないまま
//! 判定を素通りする。全体が零であることをここで落とし、以後の判定は有限の値だけを受け取る。
//!
//! 実測では同じ割り算が入口ごとに書かれており、分母の零を見る入口と見ない入口が混じっていた。

use super::error::{割合の破れ, 検収エラー};

/// 注意: 有限であることがこの型の不変条件である。構築は`部分と全体から求める`だけを通す。
#[repr(transparent)]
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub struct 画素の占める割合(f64);

impl 画素の占める割合 {
    /// 全体に対して部分が占める割合を求める。
    ///
    /// 注意: 画素数を`u32`へ写してから割るのは、`u64`から`f64`への変換が桁を落とすためである。
    /// 40億画素を超える絵は書き出しの側が持たないため、収まらない画素数は型付きエラーで落とす。
    pub fn 部分と全体から求める(部分: usize, 全体: usize) -> Result<Self, 検収エラー> {
        let 収まらない誤り = || 検収エラー::割合が破れた(割合の破れ::画素数が計算へ収まらない { 部分, 全体 });
        let 全体の値 = u32::try_from(全体).map_err(|_| 収まらない誤り())?;
        if 全体の値 == 0 {
            return Err(検収エラー::割合が破れた(割合の破れ::全体が零である { 部分 }));
        }
        let 部分の値 = u32::try_from(部分).map_err(|_| 収まらない誤り())?;
        Ok(Self(f64::from(部分の値) / f64::from(全体の値)))
    }

    /// 判定と要約の文面が読む値。生の`f64`へ戻るのはここだけである。
    pub const fn 値(self) -> f64 {
        self.0
    }
}
