//! 描画フレーム数: 1回の起動で描き切る枚数。読み戻すのは最後の1枚であり、それまでの枚数が
//! ストリーミングと時間再構成を落ち着かせる。
//!
//! 裸の数で配らないのは、0枚が「読み戻す最後の1枚が存在しない指定」であり、その破れが書き出しの無いまま
//! 読み戻しへ進んで「ファイルが無い」という遠い失敗に化けるためである。

#[repr(transparent)]
#[derive(Clone, Copy, PartialEq, Eq)]
pub struct 描画フレーム数(u32);

impl 描画フレーム数 {
    /// 注意: 枚数は原文のリテラルであるため、0枚の破れは書き誤りであり、定数として使う限りコンパイル時に落ちる。
    pub const fn 生成する(枚数: u32) -> Self {
        assert!(枚数 > 0, "描画フレーム数が0である");
        Self(枚数)
    }

    /// アプリの`--frames`へ渡す綴り。生の綴りへ戻るのはここだけである。
    pub(super) fn 綴り(self) -> String {
        self.0.to_string()
    }
}
