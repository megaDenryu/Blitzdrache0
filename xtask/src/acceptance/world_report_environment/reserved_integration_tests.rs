//! 予約された選択肢の型付きエラーが、実行環境の口からそのまま返ることの反証。呼ばれるのは`cargo test`だけである。
//!
//! 起動指定の検証だけを直に呼ぶ試験では、この経路の破れを捕まえられない。実行環境が先にセッションを作ってから
//! 検証していると、早期returnで未終了のセッションが破棄され、閉じ忘れのpanicが型付きエラーを隠す。
//! ここは実行環境の口を通し、panicせずに誤りが返ることを見る。
//!
//! 前提: 検証は起動より先に済むため、この試験はアプリを1度も起こさない。起こしていれば時間で分かる。

#![allow(clippy::unwrap_used)]

use super::世界を読ませて報告を採る実行環境;
use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 検収の実行名, 検収シーン名
};
use crate::verify::{検証の出力の置き場名, 検証の出力ルート};

const 検査のシーン: 検収シーン名 = 検収シーン名::生成する("quad");
const 検査の枚数: 描画フレーム数 = 描画フレーム数::生成する(1);
const 検査の実行名: 検収の実行名 = 検収の実行名::定数から生成する("reserved_integration");
/// この試験だけが渡す実行時形式の置き場。実際には開かれず、予約された選択肢が拒まれることだけを見る。
const 検査の置き場: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("test_reserved");

fn 実行環境を作る() -> 世界を読ませて報告を採る実行環境 {
    世界を読ませて報告を採る実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::パスから生成する(検証の出力ルート::既定().名前が指す置き場(検査の置き場)),
    )
}

/// 予約された選択肢を汎用の口から積んだ起動指定。
fn 予約を積んだ指定() -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(検査のシーン, 検査の枚数).値を持つ選択肢を足す("--scene", "terrain_origin")
}

#[test]
fn 報告を採る口は予約選択肢を型付きエラーで返す() {
    let Err(誤り) = 実行環境を作る().報告を採る(検査の実行名, &予約を積んだ指定()) else {
        panic!("予約された選択肢を積んだ指定でアプリが起きた");
    };
    assert!(誤り.to_string().contains("--scene"), "予約された選択肢を名指ししていない: {誤り}");
}

#[test]
fn 画面へ流したまま走らせる口も予約選択肢を型付きエラーで返す() {
    let Err(誤り) = 実行環境を作る().画面へ流したまま走らせる(検査の実行名, &予約を積んだ指定()) else {
        panic!("予約された選択肢を積んだ指定でアプリが起きた");
    };
    assert!(誤り.to_string().contains("--scene"), "予約された選択肢を名指ししていない: {誤り}");
}

#[test]
fn 予約を積んでいない指定はこの検査で落ちない() {
    let 指定 = アプリの起動指定::シーンと枚数を決める(検査のシーン, 検査の枚数).選択肢を足す("--no-taa");
    assert!(指定.引数列へ写す().is_ok());
}
