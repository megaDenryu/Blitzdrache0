//! 世界を読まずに報告を採る実行環境: 世界を1つも読まないアプリの起動から、終了時報告だけを得る操作サービス。
//!
//! 描画検収の実行環境と別の型にするのは、渡すものが違うためである。あちらは必ずシーンと枚数と
//! 読む世界の置き場を渡すのに対し、こちらは報告の求めの選択肢しか渡さない。1つの型へ混ぜると、
//! シーンを持たない起動のためにシーンを任意にすることになり、シーンを決めないまま描かせる呼び方が書ける。
//!
//! 数学の導出やベイク済み画像の焼き上げを報告させる入口がこれを使う。どれも画面を1枚も出さないため、
//! GPUは使ってもウィンドウは作らない。

use super::app_executable::アプリの起こし方;
use super::app_launch::アプリの起動;
use super::error::検収エラー;
use super::exit_report::終了時報告;
use super::run_name::検収の実行名;

pub struct 世界を読まずに報告を採る実行環境 {
    起こし方: アプリの起こし方,
}

impl 世界を読まずに報告を採る実行環境 {
    pub fn 作る(起こし方: アプリの起こし方) -> Self {
        Self { 起こし方 }
    }

    /// 報告の求めの選択肢だけを渡して起こし、終了時報告を得る。
    ///
    /// 検証層の指摘の確認をここで行わないのは、この口を通る入口が指摘の行を自分の判定の一部として
    /// 読むためである。読む前に落とすと、指摘の中身を告知に載せられない。
    pub fn 報告を採る(&self, 実行名: 検収の実行名, 報告の求め: &[&str]) -> Result<終了時報告, 検収エラー> {
        let mut 起動 = アプリの起動::始める(self.起こし方, 実行名);
        起動.選択肢を積む(報告の求め);
        起動.走らせて終了時報告を得る()
    }
}
