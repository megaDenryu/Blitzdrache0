//! 検収の実行名: 1回の実行を指す名前。読み戻しの書き出し先の基準名になり、失敗の文面ではその実行を名指す。
//!
//! 2つの役割を1つの型で持つのは、どの入口でも同じ綴りが両方に使われているためである。別々の裸の`&str`で
//! 配ると、書き出し先を組む名前と文面に出す名前が食い違った入口が作れてしまい、
//! 失敗の文面が指す実行のファイルが見つからなくなる。
//!
//! 検証を構築時に行うのは、この綴りがWindowsのファイル名になるためである。使えない綴りでも起動までは成功し、
//! 破れは書き出しの後の読み戻しで初めて出る。受け入れる綴りの決め事は`validation`が持ち、
//! 実行時の構築と原文の構築がどちらもそこを通る。

#[cfg(test)]
mod names_in_use_tests;
pub(super) mod validation;
#[cfg(test)]
mod validation_tests;

use std::borrow::Cow;

use super::error::検収エラー;
use validation::実行名の破れ;

/// 綴りを所有する形にするのは、この値を書き出し先と終了時報告と誤りの型がそのまま持つためである。
/// 借用で配ると、持つ側が`String`へ剥がして持ち直すことになり、型のまま運べなくなる。
/// 原文のリテラルは借りたまま持てるため、固定の名前に確保の費用は掛からない。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 検収の実行名(Cow<'static, str>);

impl 検収の実行名 {
    /// 実行時に組み立てた綴りから作る。破れは型付きエラーで返す。
    pub fn 生成する(綴り: &str) -> Result<Self, 検収エラー> {
        match validation::確かめる(綴り) {
            None => Ok(Self(Cow::Owned(綴り.to_string()))),
            Some(破れ) => Err(破れを誤りへ写す(破れ, 綴り)),
        }
    }

    /// 原文のリテラルから作る。実行のたびに組み立てない固定の名前がこの口を通る。
    ///
    /// 注意: 破れは書き誤りであるため、定数として使う限りコンパイル時に落ちる。
    pub const fn 定数から生成する(綴り: &'static str) -> Self {
        match validation::確かめる(綴り) {
            None => Self(Cow::Borrowed(綴り)),
            Some(実行名の破れ::空である) => panic!("検収の実行名が空である"),
            Some(実行名の破れ::使えない文字を含む) => {
                panic!("検収の実行名が使えない文字を含む(英数字と下線とハイフンだけを置ける)")
            }
            Some(実行名の破れ::予約された装置の名前である) => panic!("検収の実行名が予約された装置の名前である"),
        }
    }

    /// 書き出し先の基準名と失敗の文面へ埋めるための綴り。生の綴りへ戻るのはここだけである。
    pub(super) fn 綴り(&self) -> &str {
        &self.0
    }
}

/// 破れの枝を、どこがどう破れているかを添えた誤りへ写す。破れた文字を探し直すのは、
/// 検査が`const fn`であり枝に値を持てないためである。
fn 破れを誤りへ写す(破れ: 実行名の破れ, 綴り: &str) -> 検収エラー {
    match 破れ {
        実行名の破れ::空である => 検収エラー::検収の実行名が空である,
        実行名の破れ::使えない文字を含む => 検収エラー::検収の実行名が使えない文字を含む {
            名前: 綴り.to_string(),
            文字: 綴り.bytes().find(|バイト| !validation::使ってよい文字か(*バイト)).map_or('?', char::from),
        },
        実行名の破れ::予約された装置の名前である => {
            検収エラー::検収の実行名が予約された装置の名前である { 名前: 綴り.to_string() }
        }
    }
}

impl std::fmt::Display for 検収の実行名 {
    fn fmt(&self, 書き手: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(書き手, "{}", self.0)
    }
}
