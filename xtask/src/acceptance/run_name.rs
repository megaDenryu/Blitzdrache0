//! 検収の実行名: 1回の実行を指す名前。読み戻しの書き出し先の基準名になり、失敗の文面ではその実行を名指す。
//!
//! 2つの役割を1つの型で持つのは、どの入口でも同じ綴りが両方に使われているためである。別々の裸の`&str`で
//! 配ると、書き出し先を組む名前と文面に出す名前が食い違った入口が作れてしまい、
//! 失敗の文面が指す実行のファイルが見つからなくなる。
//!
//! 検証を構築時に行うのは、区切りや空白を含む綴りが書き出し先のパスを別の場所へ曲げ、
//! それでも起動までは成功してしまうためである。破れは書き出しの後の読み戻しで初めて出る。

#[cfg(test)]
mod validation_tests;

use super::error::検収エラー;

#[repr(transparent)]
#[derive(Clone, Copy, PartialEq, Eq)]
pub struct 検収の実行名<'名>(&'名 str);

impl<'名> 検収の実行名<'名> {
    pub fn 生成する(綴り: &'名 str) -> Result<Self, 検収エラー> {
        if 綴り.is_empty() {
            return Err(検収エラー::検収の実行名が空である);
        }
        if let Some(記号) = 綴り.chars().find(|文字| 使えない記号か(*文字)) {
            return Err(検収エラー::検収の実行名が使えない記号を含む {
                名前: 綴り.to_string(),
                記号,
            });
        }
        Ok(Self(綴り))
    }

    /// 原文のリテラルから作る。実行のたびに組み立てない固定の名前がこの口を通る。
    ///
    /// 注意: 破れは書き誤りであるため、定数として使う限りコンパイル時に落ちる。
    pub const fn 定数から生成する(綴り: &'static str) -> Self {
        assert!(!綴り.is_empty(), "検収の実行名が空である");
        let バイト列 = 綴り.as_bytes();
        let mut 位置 = 0;
        while 位置 < バイト列.len() {
            let 文字 = バイト列[位置];
            assert!(文字 != b'/' && 文字 != b'\\' && 文字 != b':', "検収の実行名が区切りを含む");
            assert!(!文字.is_ascii_whitespace(), "検収の実行名が空白を含む");
            位置 += 1;
        }
        Self(綴り)
    }

    /// 検証済みの綴りから作り直す。検証を通った綴りを保持している型だけが使う。
    ///
    /// 前提: 渡す綴りは`生成する`か`定数から生成する`を通ったものであること。
    pub(super) const fn 検証済みの綴りから作る(綴り: &'名 str) -> Self {
        Self(綴り)
    }

    /// 書き出し先の基準名と失敗の文面へ埋めるための綴り。生の綴りへ戻るのはここだけである。
    pub(super) fn 綴り(self) -> &'名 str {
        self.0
    }
}

/// 実行名に置けない文字。区切りは書き出し先を別のディレクトリへ曲げ、空白と制御文字は
/// コマンドの引数として1語にならない。
fn 使えない記号か(文字: char) -> bool {
    matches!(文字, '/' | '\\' | ':') || 文字.is_whitespace() || 文字.is_control()
}

impl std::fmt::Display for 検収の実行名<'_> {
    fn fmt(&self, 書き手: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(書き手, "{}", self.0)
    }
}
