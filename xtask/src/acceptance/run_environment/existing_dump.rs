//! 置き場に既に書かれている書き出しを扱う操作。触れるのは実行環境の`出力ディレクトリ`だけであり、
//! アプリを1度も起こさない。
//!
//! これらを分けるのは、呼び出しのタイミングが起こす操作と明確に違うためである。1回の起動が名前を変えて
//! 2枚以上を書き出す検収と、束ごとに撮って測って捨てる検収が、起こし終えた後にこの口を通る。
//!
//! 注意: どの口も、その名前の書き出しが実在することを呼び出し側が知っていることを前提にする。
//! 実在しなければ読めないことを型付きエラーで返す。

use std::path::PathBuf;

use super::super::dump_format::書き出しの形式;
use super::super::error::検収エラー;
use super::super::readback_hdr_image::圧縮前のHDR画像;
use super::super::readback_image::読み戻し画像;
use super::super::run_name::検収の実行名;
use super::描画検収の実行環境;

impl 描画検収の実行環境 {
    /// 同じ置き場に既に書かれている別名の書き出しを読む。1回の起動が2枚以上を書き出す検収がこれを使う。
    pub fn 同じ置き場の書き出しを読み戻す(&self, 実行名: 検収の実行名) -> Result<読み戻し画像, 検収エラー> {
        読み戻し画像::読み込む(&self.出力ディレクトリ.中の書き出し先(実行名))
    }

    /// 同じ置き場に既に書かれている、明るさの圧縮を通す前の書き出しを読む。
    pub fn 同じ置き場の圧縮前の画素を読み戻す(
        &self, 実行名: 検収の実行名
    ) -> Result<圧縮前のHDR画像, 検収エラー> {
        圧縮前のHDR画像::読み込む(&self.出力ディレクトリ.中の書き出し先(実行名))
    }

    /// 同じ置き場に既に書かれている書き出しのバイト列。形式ごとの読み手をまだ型で持てていない判定が読む。
    pub fn 同じ置き場の書き出しのバイト列を読む(
        &self,
        実行名: 検収の実行名,
        形式: 書き出しの形式,
    ) -> Result<Vec<u8>, 検収エラー> {
        let パス = self.出力ディレクトリ.中の書き出し先(実行名).形式のパス(形式);
        std::fs::read(&パス).map_err(|誤り| 検収エラー::読み戻しのファイルを読めない { パス, 誤り })
    }

    /// 同じ置き場に既に書かれている書き出しをPNGへ変換して、絵の置き場を返す。
    pub fn 同じ置き場の書き出しを目視用の絵へ変換する(&self, 実行名: 検収の実行名) -> Result<PathBuf, 検収エラー> {
        self.出力ディレクトリ.中の書き出し先(実行名).目視用の絵へ変換する()
    }

    /// 読み終えた書き出しを捨てる。消せなかったことを失敗にしないのは、次の束が同じ名前へ書くわけではなく、
    /// 残っても判定に混ざらないためである。消す目的は置き場の占有を1束ぶんに抑えることだけである。
    pub fn 同じ置き場の書き出しを捨てる(&self, 実行名: 検収の実行名) {
        self.出力ディレクトリ.中の書き出し先(実行名).書き出したファイルを消す();
    }
}
