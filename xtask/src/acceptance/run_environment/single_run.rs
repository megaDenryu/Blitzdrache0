//! 検収の1回の実行: 1条件を1回走らせた成果。報告と絵と、その絵の置き場を対で持つ型である。
//!
//! 3つをまとめて持つのは、報告を読む判定と絵を読む判定と絵をPNGへ変換する工程が、どれも「同じ1回の実行の」
//! ものであることを前提にするためである。別々に返すと、別の実行の報告と絵を突き合わせる呼び方が書ける。

use super::super::exit_report::終了時報告;
use super::super::readback_dump::読み戻しの書き出し先;
use super::super::readback_image::読み戻し画像;

pub struct 検収の1回の実行 {
    報告: 終了時報告,
    画像: 読み戻し画像,
    書き出し先: 読み戻しの書き出し先,
}

impl 検収の1回の実行 {
    /// 実行環境を通さずに起こした入口が、自分で集めた3つをこの型へまとめるための口である。
    /// 構造是正計画の順2の第2工程で全コマンドが実行環境を通ると、この口は要らなくなる。
    pub fn 組み立てる(報告: 終了時報告, 画像: 読み戻し画像, 書き出し先: 読み戻しの書き出し先) -> Self {
        Self {
            報告, 画像, 書き出し先
        }
    }

    pub fn 報告(&self) -> &終了時報告 {
        &self.報告
    }

    pub fn 画像(&self) -> &読み戻し画像 {
        &self.画像
    }

    pub fn 書き出し先(&self) -> &読み戻しの書き出し先 {
        &self.書き出し先
    }

    /// 絵だけを持ち出す。報告を読まない判定が、絵の所有を受け取るための口である。
    pub fn 画像を取り出す(self) -> 読み戻し画像 {
        self.画像
    }
}
