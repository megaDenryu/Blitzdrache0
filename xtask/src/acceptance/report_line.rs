//! 報告の行: 終了時報告から取り出した1行を所有する型。
//!
//! 行を裸の`&str`で配ると、受け取った側がそれぞれの流儀で語を切って数へ写す。実測ではその署名が
//! 61箇所へ流れており、鍵の探し方(完全一致か末尾一致か等号か)も入口ごとに違っていた。
//!
//! 実行名を一緒に持つのは、失敗の文面が「どの実行の報告の行か」を必ず言うためである。
//! 行の原文を所有するのは、この行が終了時報告の寿命より長く生きる読み取りがあるためである。
//!
//! 鍵で引く値の読み取りは`value_by_key`が持つ。

mod value_by_key;

use super::error::{報告の読み取りの破れ, 検収エラー};
use super::run_name::検収の実行名;

pub struct 報告の行 {
    実行名: 検収の実行名,
    原文: String,
}

impl 報告の行 {
    pub(super) fn 取り込む(実行名: &検収の実行名, 原文: &str) -> Self {
        Self {
            実行名: 実行名.clone(),
            原文: 原文.to_string(),
        }
    }

    /// 行の原文。綴りどうしの一致を見る判定と、まだ型で持てていない読み取りが受け取る口である。
    pub fn 原文(&self) -> &str {
        &self.原文
    }

    /// 読み取りの破れへ実行名を添えて検収エラーにする。どの実行の報告の行かを、受け取る側が組み立て直さずに言える。
    fn 破れを包む(&self, 破れ: 報告の読み取りの破れ) -> 検収エラー {
        検収エラー::報告の読み取りが破れた {
            実行名: self.実行名.clone(),
            破れ,
        }
    }
}
