//! 世界を読ませて報告を採る実行環境: アプリに世界を描かせ、絵を書き出させずに終了時報告だけを得る操作サービス。
//!
//! 絵を書き出す実行環境と分けるのは、保持するものが違うためである。絵を読む検収は書き出しの置き場を必ず持つのに対し、
//! 報告の行だけを読む検収は置き場を1つも要らない。1つの型へ混ぜると、使われない置き場のディレクトリが
//! 実行のたびに作られ、その置き場が空であることを誰も説明できなくなる。
//!
//! 絵を読む検収はこの型を内側に持って置き場を足す。起こし方とアセットルートの保持を1つにするためである。

use super::app_executable::アプリの起こし方;
use super::app_launch::アプリの起動;
use super::error::検収エラー;
use super::exit_report::終了時報告;
use super::launch_specification::アプリの起動指定;
use super::run_name::検収の実行名;
use super::runtime_asset_root::実行時アセットルート;

pub struct 世界を読ませて報告を採る実行環境 {
    起こし方: アプリの起こし方,
    アセットルート: 実行時アセットルート,
}

impl 世界を読ませて報告を採る実行環境 {
    pub fn 作る(起こし方: アプリの起こし方, アセットルート: 実行時アセットルート) -> Self {
        Self {
            起こし方, アセットルート
        }
    }

    /// 1条件を描かせて報告だけを採る。検証層の指摘が残っていれば報告を読む前に落とす。
    pub fn 報告を採る(&self, 実行名: 検収の実行名, 指定: &アプリの起動指定) -> Result<終了時報告, 検収エラー> {
        let 報告 = self.起動を組む(指定, 実行名).走らせて終了時報告を得る()?;
        報告.検証層の指摘が零件であることを確かめる()?;
        Ok(報告)
    }

    /// 起動指定とアセットルートまでを積んだ起動。書き出し先を足すのは絵を読む実行環境の仕事である。
    pub(super) fn 起動を組む(&self, 指定: &アプリの起動指定, 実行名: 検収の実行名) -> アプリの起動 {
        let mut 起動 = アプリの起動::始める(self.起こし方, 実行名);
        起動.起動指定を積む(指定);
        起動.読む世界の置き場を積む(&self.アセットルート);
        起動
    }
}
