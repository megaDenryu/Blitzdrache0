//! 世界を読ませて報告を採る実行環境: アプリに世界を描かせ、絵を書き出させずに終了時報告だけを得る操作サービス。
//!
//! 絵を書き出す実行環境と分けるのは、保持するものが違うためである。絵を読む検収は書き出しの置き場を必ず持つのに対し、
//! 報告の行だけを読む検収は置き場を1つも要らない。1つの型へ混ぜると、使われない置き場のディレクトリが
//! 実行のたびに作られ、その置き場が空であることを誰も説明できなくなる。
//!
//! 絵を読む検収はこの型を内側に持って置き場を足す。起こし方とアセットルートの保持を1つにするためである。

#[cfg(test)]
mod reserved_integration_tests;

use super::app_executable::アプリの起こし方;
use super::app_launch::アプリの起動;
use super::error::検収エラー;
use super::exit_report::終了時報告;
use super::launch_specification::アプリの起動指定;
use super::run_name::検収の実行名;
use super::runtime_asset_root::実行時アセットルート;

/// 読む世界の置き場を誰が決めるか。検収が明示する場合と、アプリの既定へ任せる場合がある。
///
/// `Option`で持たないのは、無しが「置き場を決めていない」のか「置き場が要らない」のかが型から決まらないためである。
enum 読む世界の置き場の決め方 {
    検収が名指しする(実行時アセットルート), // どの世界を読むかを実行環境が決める
    アプリの既定に任せる,                   // 既定の世界だけを読む検収がこれを使い、既定の綴りをxtaskへ写さない
}

pub struct 世界を読ませて報告を採る実行環境 {
    起こし方: アプリの起こし方,
    置き場: 読む世界の置き場の決め方,
}

impl 世界を読ませて報告を採る実行環境 {
    pub fn 作る(起こし方: アプリの起こし方, アセットルート: 実行時アセットルート) -> Self {
        Self {
            起こし方,
            置き場: 読む世界の置き場の決め方::検収が名指しする(アセットルート),
        }
    }

    /// 読む世界の置き場をアプリの既定へ任せて作る。既定の世界だけを読む検収がこの口を通る。
    pub fn 世界の置き場をアプリの既定に任せて作る(起こし方: アプリの起こし方) -> Self {
        Self {
            起こし方,
            置き場: 読む世界の置き場の決め方::アプリの既定に任せる,
        }
    }

    /// 1条件を描かせて報告だけを採る。検証層の指摘が残っていれば報告を読む前に落とす。
    pub fn 報告を採る(&self, 実行名: 検収の実行名, 指定: &アプリの起動指定) -> Result<終了時報告, 検収エラー> {
        let 報告 = self.起動を組む(指定, 実行名)?.走らせて終了時報告を得る()?;
        報告.検証層の指摘が零件であることを確かめる()?;
        Ok(報告)
    }

    /// 出力を捕まえずに画面へ流したまま走らせ、終わりを待つ。報告は返さない。
    ///
    /// 人が閉じるまで遊ぶ実行と、進み具合を見ながら通すスモークの実行がこの口を通る。
    /// 出力を溜めないのは、長い実行の途中経過をその場で見せるためである。
    pub fn 画面へ流したまま走らせる(
        &self, 実行名: 検収の実行名, 指定: &アプリの起動指定
    ) -> Result<(), 検収エラー> {
        self.起動を組む(指定, 実行名)?.画面へ流したまま走らせて終わりを待つ()
    }

    /// 起動指定とアセットルートまでを積んだ起動。書き出し先を足すのは絵を読む実行環境の仕事である。
    ///
    /// 起動指定の検証をセッションを始める前に済ませるのは、途中で落ちたときに未終了のセッションが
    /// 破棄されて閉じ忘れのpanicが型付きエラーを隠すためである。
    pub(super) fn 起動を組む(
        &self, 指定: &アプリの起動指定, 実行名: 検収の実行名
    ) -> Result<アプリの起動, 検収エラー> {
        let 引数 = 指定.引数列へ写す()?;
        let mut 起動 = アプリの起動::始める(self.起こし方, 実行名, &引数);
        if let 読む世界の置き場の決め方::検収が名指しする(アセットルート) = &self.置き場 {
            起動.読む世界の置き場を積む(アセットルート);
        }
        Ok(起動)
    }
}
