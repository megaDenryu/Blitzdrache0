//! 描画検収の実行環境: アプリを起こして絵と報告を得る操作サービス。
//!
//! 起こし方とアセットルートと出力ディレクトリを構築時に受けて保持する。これらを条件ごとの呼び出しへ
//! 引数で持参させないのは、同じ入口の中で条件ごとに違う置き場を渡す形が成立してしまうためである。
//! 1つの入口が読む世界と、絵を溜める場所は、条件が変わっても変わらない。
//!
//! ほぼ全部の検収が踏む3手(起こす・検証層の指摘が零であることを確かめる・読み戻す)をここが1つ持つ。
//! 実測ではこの3手が61のコマンドで別々に書かれており、validationの確認を落とした入口が混じっていた。
//! 起こし方とアセットルートの保持は`世界を読ませて報告を採る実行環境`が持ち、ここはそれへ置き場を足す。
//! 既に書かれている書き出しを読む操作は`existing_dump`が、1回ぶんの成果の型は`single_run`が持つ。

mod existing_dump;
mod single_run;

use std::path::PathBuf;

pub use single_run::検収の1回の実行;

use super::app_executable::アプリの起こし方;
use super::dump_format::書き出しの形式;
use super::error::検収エラー;
use super::exit_report::終了時報告;
use super::launch_specification::アプリの起動指定;
use super::readback_dump::読み戻しの置き場;
use super::readback_hdr_image::圧縮前のHDR画像;
use super::readback_image::読み戻し画像;
use super::run_name::検収の実行名;
use super::runtime_asset_root::実行時アセットルート;
use super::world_report_environment::世界を読ませて報告を採る実行環境;

pub struct 描画検収の実行環境 {
    報告の採取: 世界を読ませて報告を採る実行環境,
    出力ディレクトリ: 読み戻しの置き場,
}

impl 描画検収の実行環境 {
    pub fn 作る(
        起こし方: アプリの起こし方, アセットルート: 実行時アセットルート, 出力ディレクトリ: PathBuf
    ) -> Result<Self, 検収エラー> {
        Self::報告の採取から作る(世界を読ませて報告を採る実行環境::作る(起こし方, アセットルート), 出力ディレクトリ)
    }

    /// 読む世界の置き場をアプリの既定へ任せて作る。既定の世界だけを描く検収がこの口を通る。
    pub fn 世界の置き場をアプリの既定に任せて作る(
        起こし方: アプリの起こし方,
        出力ディレクトリ: PathBuf,
    ) -> Result<Self, 検収エラー> {
        Self::報告の採取から作る(
            世界を読ませて報告を採る実行環境::世界の置き場をアプリの既定に任せて作る(起こし方),
            出力ディレクトリ,
        )
    }

    fn 報告の採取から作る(
        報告の採取: 世界を読ませて報告を採る実行環境, 出力ディレクトリ: PathBuf
    ) -> Result<Self, 検収エラー> {
        Ok(Self {
            報告の採取,
            出力ディレクトリ: 読み戻しの置き場::作って受け取る(出力ディレクトリ)?,
        })
    }

    /// 1条件を描いて読み戻す。検証層の指摘が残っていれば絵を読む前に落とす。
    pub fn 描いて読み戻す(
        &self, 実行名: 検収の実行名, 指定: &アプリの起動指定
    ) -> Result<検収の1回の実行, 検収エラー> {
        let 書き出し先 = self.出力ディレクトリ.中の書き出し先(実行名.clone());
        let 報告 = self.書き出させて報告を採る(実行名, 指定, 書き出しの形式::提示画像)?;
        let 画像 = 読み戻し画像::読み込む(&書き出し先)?;
        Ok(検収の1回の実行::組み立てる(報告, 画像, 書き出し先))
    }

    /// 1条件を明るさの圧縮を通す前の単精度で描いて読み戻す。項ごとの比を測る判定がこれを使う。
    pub fn 圧縮前の画素で描いて読み戻す(
        &self,
        実行名: 検収の実行名,
        指定: &アプリの起動指定,
    ) -> Result<圧縮前のHDR画像, 検収エラー> {
        let 書き出し先 = self.出力ディレクトリ.中の書き出し先(実行名.clone());
        self.書き出させて報告を採る(実行名, 指定, 書き出しの形式::明るさの圧縮前)?;
        圧縮前のHDR画像::読み込む(&書き出し先)
    }

    /// 書き出させたうえで報告だけを採る。書き出したファイルは置き場に残るが、この口は読み戻さない。
    /// 書き出させること自体がアプリの集計の前提になる検収と、1回の起動が名前を変えて何枚も書き出す検収が使う。
    pub fn 書き出させて報告を採る(
        &self,
        実行名: 検収の実行名,
        指定: &アプリの起動指定,
        形式: 書き出しの形式,
    ) -> Result<終了時報告, 検収エラー> {
        let 書き出し先 = self.出力ディレクトリ.中の書き出し先(実行名);
        let mut 起動 = self.報告の採取.起動を組む(指定, 書き出し先.実行名().clone())?;
        起動.書き出し先を積む(&書き出し先, 形式);
        let 報告 = 起動.走らせて終了時報告を得る()?;
        報告.検証層の指摘が零件であることを確かめる()?;
        Ok(報告)
    }
}
