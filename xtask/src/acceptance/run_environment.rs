//! 描画検収の実行環境: アプリを起こして絵と報告を得る操作サービス。
//!
//! 起こし方とアセットルートと出力ディレクトリを構築時に受けて保持する。これらを条件ごとの呼び出しへ
//! 引数で持参させないのは、同じ入口の中で条件ごとに違う置き場を渡す形が成立してしまうためである。
//! 1つの入口が読む世界と、絵を溜める場所は、条件が変わっても変わらない。
//!
//! ほぼ全部の検収が踏む3手(起こす・検証層の指摘が零であることを確かめる・読み戻す)をここが1つ持つ。
//! 実測ではこの3手が61のコマンドで別々に書かれており、validationの確認を落とした入口が混じっていた。
//! 起動そのものの工程は`launch`が持つ。

mod launch;

use std::path::PathBuf;

use super::app_executable::アプリの起こし方;
use super::error::検収エラー;
use super::exit_report::終了時報告;
use super::launch_specification::アプリの起動指定;
use super::readback_dump::{読み戻しの書き出し先, 読み戻しの置き場};
use super::readback_image::読み戻し画像;
use super::run_name::検収の実行名;
use super::runtime_asset_root::実行時アセットルート;

/// 1条件を1回走らせた成果。報告と絵と、その絵の置き場を対で持つ。
pub struct 検収の1回の実行 {
    報告: 終了時報告,
    画像: 読み戻し画像,
    書き出し先: 読み戻しの書き出し先,
}

impl 検収の1回の実行 {
    /// 実行環境を通さずに起こした入口が、自分で集めた3つをこの型へまとめるための口である。
    /// 構造是正計画の順2の第2工程で全コマンドが実行環境を通ると、この口は要らなくなる。
    pub fn 組み立てる(報告: 終了時報告, 画像: 読み戻し画像, 書き出し先: 読み戻しの書き出し先) -> Self {
        Self {
            報告, 画像, 書き出し先
        }
    }

    pub fn 報告(&self) -> &終了時報告 {
        &self.報告
    }

    pub fn 画像(&self) -> &読み戻し画像 {
        &self.画像
    }

    pub fn 書き出し先(&self) -> &読み戻しの書き出し先 {
        &self.書き出し先
    }

    /// 絵だけを持ち出す。報告を読まない判定が、絵の所有を受け取るための口である。
    pub fn 画像を取り出す(self) -> 読み戻し画像 {
        self.画像
    }
}

pub struct 描画検収の実行環境 {
    起こし方: アプリの起こし方,
    アセットルート: 実行時アセットルート,
    出力ディレクトリ: 読み戻しの置き場,
}

impl 描画検収の実行環境 {
    pub fn 作る(
        起こし方: アプリの起こし方, アセットルート: 実行時アセットルート, 出力ディレクトリ: PathBuf
    ) -> Result<Self, 検収エラー> {
        Ok(Self {
            起こし方,
            アセットルート,
            出力ディレクトリ: 読み戻しの置き場::作って受け取る(出力ディレクトリ)?,
        })
    }

    /// 1条件を描いて読み戻す。検証層の指摘が残っていれば絵を読む前に落とす。
    pub fn 描いて読み戻す(
        &self, 実行名: 検収の実行名<'_>, 指定: &アプリの起動指定
    ) -> Result<検収の1回の実行, 検収エラー> {
        let 書き出し先 = self.出力ディレクトリ.中の書き出し先(実行名);
        let 報告 = launch::起こして終了時報告を得る(self.起こし方, &self.アセットルート, 実行名, 指定, &書き出し先)?;
        報告.検証層の指摘が零件であることを確かめる()?;
        let 画像 = 読み戻し画像::読み込む(&書き出し先)?;
        Ok(検収の1回の実行 {
            報告, 画像, 書き出し先
        })
    }
}
