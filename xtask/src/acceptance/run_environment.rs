//! 描画検収の実行環境: アプリを起こして絵と報告を得る操作サービス。
//!
//! 起こし方とアセットルートと出力ディレクトリを構築時に受けて保持する。これらを条件ごとの呼び出しへ
//! 引数で持参させないのは、同じ入口の中で条件ごとに違う置き場を渡す形が成立してしまうためである。
//! 1つの入口が読む世界と、絵を溜める場所は、条件が変わっても変わらない。
//!
//! ほぼ全部の検収が踏む3手(起こす・検証層の指摘が零であることを確かめる・読み戻す)をここが1つ持つ。
//! 実測ではこの3手が61のコマンドで別々に書かれており、validationの確認を落とした入口が混じっていた。
//! 起こし方とアセットルートの保持は`世界を読ませて報告を採る実行環境`が持ち、ここはそれへ置き場を足す。
//! 起動そのものの工程は`app_launch`が、1回ぶんの成果の型は`single_run`が持つ。

mod single_run;

use std::path::PathBuf;

pub use single_run::検収の1回の実行;

use super::app_executable::アプリの起こし方;
use super::error::検収エラー;
use super::launch_specification::アプリの起動指定;
use super::readback_dump::読み戻しの置き場;
use super::readback_image::読み戻し画像;
use super::run_name::検収の実行名;
use super::runtime_asset_root::実行時アセットルート;
use super::world_report_environment::世界を読ませて報告を採る実行環境;

pub struct 描画検収の実行環境 {
    報告の採取: 世界を読ませて報告を採る実行環境,
    出力ディレクトリ: 読み戻しの置き場,
}

impl 描画検収の実行環境 {
    pub fn 作る(
        起こし方: アプリの起こし方, アセットルート: 実行時アセットルート, 出力ディレクトリ: PathBuf
    ) -> Result<Self, 検収エラー> {
        Ok(Self {
            報告の採取: 世界を読ませて報告を採る実行環境::作る(起こし方, アセットルート),
            出力ディレクトリ: 読み戻しの置き場::作って受け取る(出力ディレクトリ)?,
        })
    }

    /// 1条件を描いて読み戻す。検証層の指摘が残っていれば絵を読む前に落とす。
    pub fn 描いて読み戻す(
        &self, 実行名: 検収の実行名, 指定: &アプリの起動指定
    ) -> Result<検収の1回の実行, 検収エラー> {
        let 書き出し先 = self.出力ディレクトリ.中の書き出し先(実行名);
        let mut 起動 = self.報告の採取.起動を組む(指定, 書き出し先.実行名().clone());
        起動.画素の書き出し先を積む(&書き出し先);
        let 報告 = 起動.走らせて終了時報告を得る()?;
        報告.検証層の指摘が零件であることを確かめる()?;
        let 画像 = 読み戻し画像::読み込む(&書き出し先)?;
        Ok(検収の1回の実行::組み立てる(報告, 画像, 書き出し先))
    }

    /// 同じ置き場に既に書かれている別名の書き出しを読む。1回の起動が2枚以上を書き出す検収がこれを使う。
    pub fn 同じ置き場の書き出しを読み戻す(&self, 実行名: 検収の実行名) -> Result<読み戻し画像, 検収エラー> {
        読み戻し画像::読み込む(&self.出力ディレクトリ.中の書き出し先(実行名))
    }
}
