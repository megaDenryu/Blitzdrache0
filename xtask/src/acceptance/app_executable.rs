//! アプリの起こし方: 検収がblitz_appを起こす2つのやり方と、その綴りを私有する型。
//!
//! リリースの実行ファイルの綴りを裸の公開定数で配ると、起動する側と由来を採る側が別々にその綴りを持つ。
//! 実測ではその定数が6つのファイルへ流れており、置き場所を変える改定が6箇所の同時変更になっていた。
//! ここが綴りを1つ持ち、起動と由来の採取という2つの使い道だけを外へ出す。

use std::path::Path;
use std::process::Command;

/// リリースの実行ファイルの置き場。生の綴りが在るのはこの1行だけである。
const リリース実行ファイルのパス: &str = "target/release/blitz_app.exe";

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum アプリの起こし方 {
    /// cargoに構築させてから起動する。デバッグ版で足りる検収がこれを使う。
    毎回cargoに構築させて起動する,
    /// あらかじめ構築したリリース版の実行ファイルを直に起動する。GPU時間を測る計測がこれを使う。
    /// 構築そのものは`release_build`が計測の前に1度だけ行う。
    構築済みのリリース版を直に起動する,
}

impl アプリの起こし方 {
    /// この起こし方でアプリを起こすコマンド。アプリ自身の引数は呼び出し側が続けて足す。
    pub fn コマンドを作る(self) -> Command {
        match self {
            Self::毎回cargoに構築させて起動する => {
                let mut コマンド = Command::new("cargo");
                コマンド.args(["run", "-p", "blitz_app", "--"]);
                コマンド
            }
            Self::構築済みのリリース版を直に起動する => Command::new(リリース実行ファイルのパス),
        }
    }

    /// 起動できなかったときの文面へ出す綴り。どちらのやり方で起こそうとして失敗したのかを言う。
    pub fn 表示の綴り(self) -> &'static str {
        match self {
            Self::毎回cargoに構築させて起動する => "cargo run",
            Self::構築済みのリリース版を直に起動する => リリース実行ファイルのパス,
        }
    }

    /// 由来を採る対象としてのリリース実行ファイル。生のパスへ戻る唯一の境界であり、
    /// 読むのは構築の由来を採る工程だけである。
    pub(crate) fn 由来を採るリリース実行ファイルのパス() -> &'static Path {
        Path::new(リリース実行ファイルのパス)
    }
}
