//! 読み戻しの置き場: アプリが最終フレームを書き出す先のディレクトリと、その中の1件ぶんの書き出し先を表す型。
//!
//! 役割を持つパスを裸の`Path`で持ち回らないのは、出力ディレクトリと1件ぶんの書き出し先を取り違えても型が通り、
//! しかも取り違えたまま`.raw`と`.size`を組んでしまうためである。拡張子の綴りはこの型だけが知る。
//!
//! アプリは1件の書き出しを`<基準名>.raw`(RGBA8の連結)と`<基準名>.size`(幅 高さ)の2ファイルへ分ける。
//! 読む側も対で扱うため、基準名を持つ型を1つ置いて、2つのパスをそこから組む。

use std::path::{Path, PathBuf};

use super::error::検収エラー;
use super::run_name::検収の実行名;

/// 1つの入口が読み戻しを溜めるディレクトリ。作れることを構築時に確かめる。
#[repr(transparent)]
pub struct 読み戻しの置き場(PathBuf);

impl 読み戻しの置き場 {
    /// 無ければ作ってから受け取る。作れないまま起動へ進むと、アプリが書き出しに失敗した理由が遠くで出る。
    pub fn 作って受け取る(ディレクトリ: PathBuf) -> Result<Self, 検収エラー> {
        std::fs::create_dir_all(&ディレクトリ).map_err(|誤り| 検収エラー::出力ディレクトリを作れなかった {
            パス: ディレクトリ.clone(),
            誤り,
        })?;
        Ok(Self(ディレクトリ))
    }

    pub fn 中の書き出し先(&self, 実行名: 検収の実行名) -> 読み戻しの書き出し先 {
        読み戻しの書き出し先::組み立てる(self.0.join(実行名.綴り()), 実行名)
    }
}

/// 読み戻し1件ぶんの書き出し先。拡張子を持たない基準名までのパスと、その実行を指す名前を持ち、
/// 対の2ファイルをここから組む。
///
/// 名前をパスと一緒に持つのは、この書き出しを生んだ実行を失敗の文面が名指すためである。
/// 名前を別に配ると、書き出し先を組んだ名前と文面に出す名前が食い違った入口が作れてしまう。
pub struct 読み戻しの書き出し先 {
    基準名までのパス: PathBuf,
    実行名: 検収の実行名,
}

impl 読み戻しの書き出し先 {
    const 画素の拡張子: &'static str = "raw";
    const 寸法の拡張子: &'static str = "size";

    /// 出力ディレクトリと実行名から決める。実行環境をまだ通っていない入口が書き出し先を組むための口である。
    /// 構造是正計画の順2の第2工程で全コマンドが実行環境を通ると、この口は要らなくなる。
    pub fn 出力ディレクトリの中に決める(出力ディレクトリ: &Path, 実行名: 検収の実行名) -> Self {
        Self::組み立てる(出力ディレクトリ.join(実行名.綴り()), 実行名)
    }

    fn 組み立てる(基準名までのパス: PathBuf, 実行名: 検収の実行名) -> Self {
        Self {
            基準名までのパス, 実行名
        }
    }

    /// この書き出しを生んだ実行の名前。失敗の文面がこれを読む。
    pub fn 実行名(&self) -> &検収の実行名 {
        &self.実行名
    }

    pub(super) fn 画素のパス(&self) -> PathBuf {
        self.基準名までのパス.with_extension(Self::画素の拡張子)
    }

    pub(super) fn 寸法のパス(&self) -> PathBuf {
        self.基準名までのパス.with_extension(Self::寸法の拡張子)
    }

    /// アプリの`--dump-frame`へ渡す綴り。プロセス境界へ生のパスが出る唯一の場所である。
    pub fn 起動引数として渡す綴り(&self) -> &Path {
        &self.基準名までのパス
    }

    /// この書き出しをPNGへ変換して、絵の置き場を返す。親エージェントの目視は生のRGBA8を開けないため、
    /// 絵を要る入口がこの口を通る。変換の工程へ生のパスを渡すのはこの型の中だけである。
    pub fn 目視用の絵へ変換する(&self) -> Result<PathBuf, 検収エラー> {
        crate::raw_png::変換する(&self.基準名までのパス).map_err(|理由| 検収エラー::目視用の絵へ変換できなかった {
            書き出し先: self.基準名までのパス.clone(),
            理由,
        })
    }
}
