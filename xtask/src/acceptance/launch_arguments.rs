//! 完成した起動引数: 予約された選択肢が混じっていないことを確かめ済みの引数列。
//!
//! この型を通さないとセッションを始められない形にするのは、検証をセッションの中で行うと、検証が落ちたときに
//! 未終了のセッションが破棄されて閉じ忘れのpanicが起き、約束した型付きエラーが呼び出し元へ返らないためである。
//! 検証を先に済ませ、通った引数列だけをセッションへ渡す。
//!
//! 世界を読む起動(`アプリの起動指定`が組む)と世界を読まない起動(報告の求めだけを渡す)の両方がこの型を作る。
//! 2つの経路が同じ判定を通ることで、片方だけが予約された選択肢を素通しする状態が作れない。

use std::ffi::OsString;
use std::process::Command;

use super::error::検収エラー;
use super::reserved_option::{予約された選択肢か, 予約された選択肢の綴り一覧};

#[repr(transparent)]
pub(super) struct 完成した起動引数(Vec<OsString>);

impl 完成した起動引数 {
    /// 起動指定が組んだ並びを受け取る。予約された選択肢の検査は積む側が済ませてあり、その結果をここが受ける。
    pub(super) fn 検査済みの並びから受け取る(並び: Vec<OsString>) -> Self {
        Self(並び)
    }

    /// 世界を読まない起動の報告の求めを検証して受け取る。生の語をそのまま起動へ渡す経路が
    /// 構造用の選択肢を素通しできないよう、ここで同じ判定を通す。
    pub(super) fn 報告の求めを検証して受け取る(報告の求め: &[&str]) -> Result<Self, 検収エラー> {
        for 綴り in 報告の求め {
            if 予約された選択肢か(綴り) {
                return Err(予約を積んだ誤り(綴り));
            }
        }
        Ok(Self(報告の求め.iter().map(OsString::from).collect()))
    }

    pub(super) fn コマンドへ並べる(&self, コマンド: &mut Command) {
        コマンド.args(&self.0);
    }
}

/// 予約された選択肢を汎用の口から積んだときの誤り。文面へ予約の一覧を並べるのは、読み手が次に何を直せばよいかを
/// 決められるようにするためである。組み立てを1箇所に置き、2つの経路が同じ文面を出す。
pub(super) fn 予約を積んだ誤り(綴り: &str) -> 検収エラー {
    検収エラー::予約された選択肢を汎用の口から積んだ {
        綴り: 綴り.to_string(),
        予約の一覧: 予約された選択肢の綴り一覧().join(" "),
    }
}
