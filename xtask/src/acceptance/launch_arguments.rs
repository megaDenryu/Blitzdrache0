//! 完成した起動引数: 汎用の口から来た語に予約された選択肢が混じっていないことを確かめ済みの引数列。
//! 構造用の予約選択肢(シーン・枚数・書き出し先など)は、この型自身が型付きの材料から正当に組み立てて並べる。
//!
//! この型を通さないとセッションを始められない形にするのは、検証をセッションの中で行うと、検証が落ちたときに
//! 未終了のセッションが破棄されて閉じ忘れのpanicが起き、約束した型付きエラーが呼び出し元へ返らないためである。
//!
//! 並びの組み立てまでこの型に閉じるのは、包むだけの口を外へ出すと「未検証の指定でセッションを作れない」ことが
//! 型の不変条件でなく呼び出し側の前提に落ちるためである。組み立て済みの並びを受け取る口は1つも無く、
//! 材料(型付きのシーン・描き終わり・検査対象の選択肢)だけを受けてここが自分で検証して並べる。
//!
//! 世界を読む起動と世界を読まない起動の両方がこの型を作る。2つの経路が同じ判定を通ることで、
//! 片方だけが予約された選択肢を素通しする状態が作れない。

use std::ffi::{OsStr, OsString};
use std::process::Command;

use super::draw_end::描き終わりの決め方;
use super::error::検収エラー;
use super::launch_specification::シーンの選択肢の綴り;
use super::reserved_option::{予約された選択肢か, 予約された選択肢の綴り一覧};
use super::scene_name::検収シーン名;

/// 注意: 汎用の口から来た語に予約された選択肢が混じっていないことがこの型の不変条件である
/// (構造用の予約選択肢は型が自分で組み立てるため完成列には正当に含まれる)。
/// 構築の口は下の2つだけであり、どちらも検証を通す。並びをそのまま包む口は置かない。
#[repr(transparent)]
pub(super) struct 完成した起動引数(Vec<OsString>);

impl 完成した起動引数 {
    /// 世界を描く起動の引数列。シーンと描き終わりは型が組み立て、汎用の口から積まれた選択肢だけを検証する。
    pub(super) fn 世界を描く起動から作る(
        シーン名: 検収シーン名,
        描き終わり: &描き終わりの決め方,
        汎用の口から積まれた選択肢: &[OsString],
    ) -> Result<Self, 検収エラー> {
        予約が混じっていないことを確かめる(汎用の口から積まれた選択肢.iter().map(OsString::as_os_str))?;
        let mut 並び = vec![OsString::from(シーンの選択肢の綴り), OsString::from(シーン名.綴り())];
        描き終わり.引数列へ足す(&mut 並び);
        並び.extend(汎用の口から積まれた選択肢.iter().cloned());
        Ok(Self(並び))
    }

    /// 世界を読まない起動の引数列。報告の求めだけを渡す経路が構造用の選択肢を素通しできないよう、
    /// 生の語をここで検証する。
    pub(super) fn 報告の求めから作る(報告の求め: &[&str]) -> Result<Self, 検収エラー> {
        予約が混じっていないことを確かめる(報告の求め.iter().map(OsStr::new))?;
        Ok(Self(報告の求め.iter().map(OsString::from).collect()))
    }

    pub(super) fn コマンドへ並べる(&self, コマンド: &mut Command) {
        コマンド.args(&self.0);
    }
}

/// 語の並びに型の組み立てる選択肢が混じっていないことを確かめる。
///
/// 綴りへ写せない語を飛ばすのは、予約された綴りがすべてASCIIであり、写せない語がそのどれとも一致しえないためである。
fn 予約が混じっていないことを確かめる<'語>(語一覧: impl Iterator<Item = &'語 OsStr>) -> Result<(), 検収エラー> {
    for 語 in 語一覧 {
        let Some(綴り) = 語.to_str() else { continue };
        if 予約された選択肢か(綴り) {
            return Err(予約を積んだ誤り(綴り));
        }
    }
    Ok(())
}

/// 予約された選択肢を汎用の口から積んだときの誤り。文面へ予約の一覧を並べるのは、読み手が次に何を直せばよいかを
/// 決められるようにするためである。組み立てを1箇所に置き、2つの経路が同じ文面を出す。
fn 予約を積んだ誤り(綴り: &str) -> 検収エラー {
    検収エラー::予約された選択肢を汎用の口から積んだ {
        綴り: 綴り.to_string(),
        予約の一覧: 予約された選択肢の綴り一覧().join(" "),
    }
}
