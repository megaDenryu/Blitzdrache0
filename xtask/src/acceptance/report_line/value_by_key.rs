//! 報告の行の中で、鍵に結ばれた値を読む口。触れるのは原文と、破れを包む親のメソッドだけである。
//!
//! 値の型ごとに口を分けるのは、報告が同じ行の中で数と綴りと真偽を並べるためである。1つの口で綴りだけを返すと、
//! 受け取った側が数への変換と真偽の読み替えをそれぞれの流儀で書き直すことになり、それが実測の姿だった。
//!
//! 鍵に値が結ばれる形を引数で受けるのは、行によって「鍵 値」「鍵=値」「鍵に触れた語の次」「鍵に続く残り」の
//! 4通りがあるためである。どの形かは行の書式を知っている呼び出し側だけが決められる。

use super::報告の行;
use crate::acceptance::error::{報告の読み取りの破れ, 検収エラー};
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形, 鍵に結ばれた語の在り処};

impl 報告の行 {
    /// 鍵に結ばれた値を数として読む。読む数の型は受け取る側が決める。
    pub fn 鍵に結ばれた数<数: std::str::FromStr>(
        &self, 鍵: &報告の行の鍵, 形: 鍵に値が結ばれる形
    ) -> Result<数, 検収エラー> {
        self.語を数へ写す(鍵, 形, |語| 語)
    }

    /// 鍵に結ばれた値から、前後に付いた数字でない飾り(単位や閉じ括弧)を落として数として読む。
    pub fn 鍵に結ばれた語から数字だけを読む<数: std::str::FromStr>(
        &self,
        鍵: &報告の行の鍵,
        形: 鍵に値が結ばれる形,
    ) -> Result<数, 検収エラー> {
        self.語を数へ写す(鍵, 形, |語| 語.trim_matches(|文字: char| !文字.is_ascii_digit()))
    }

    /// 鍵に結ばれた値をそのままの綴りで取り出す。数でも真偽でもない値(表記を保つ段や名前)がこの口を通る。
    pub fn 鍵に結ばれた綴り(&self, 鍵: &報告の行の鍵, 形: 鍵に値が結ばれる形) -> Result<String, 検収エラー> {
        Ok(self.語を取り出す(鍵, 形)?.to_string())
    }

    /// 鍵に結ばれた値を真偽として読む。アプリは「真」と「偽」の綴りで答える。
    pub fn 鍵に結ばれた真偽(&self, 鍵: &報告の行の鍵, 形: 鍵に値が結ばれる形) -> Result<bool, 検収エラー> {
        let 語 = self.語を取り出す(鍵, 形)?;
        match 語 {
            "真" => Ok(true),
            "偽" => Ok(false),
            _ => Err(self.破れを包む(報告の読み取りの破れ::鍵に続く語が真でも偽でもない {
                行: self.原文().to_string(),
                鍵: 鍵.clone(),
                語: 語.to_string(),
            })),
        }
    }

    fn 語を数へ写す<数: std::str::FromStr>(
        &self,
        鍵: &報告の行の鍵,
        形: 鍵に値が結ばれる形,
        整える: impl Fn(&str) -> &str,
    ) -> Result<数, 検収エラー> {
        let 語 = 整える(self.語を取り出す(鍵, 形)?);
        語.parse().map_err(|_| {
            self.破れを包む(報告の読み取りの破れ::鍵に続く語を数として読めない {
                行: self.原文().to_string(),
                鍵: 鍵.clone(),
                語: 語.to_string(),
            })
        })
    }

    fn 語を取り出す(&self, 鍵: &報告の行の鍵, 形: 鍵に値が結ばれる形) -> Result<&str, 検収エラー> {
        match 鍵.結ばれた語を探す(self.原文(), 形) {
            鍵に結ばれた語の在り処::見つかった(語) => Ok(語),
            鍵に結ばれた語の在り処::鍵が無い => Err(self.破れを包む(報告の読み取りの破れ::行に鍵が無い {
                行: self.原文().to_string(),
                鍵: 鍵.clone(),
            })),
            鍵に結ばれた語の在り処::鍵に値が続いていない => {
                Err(self.破れを包む(報告の読み取りの破れ::鍵の次に語が無い {
                    行: self.原文().to_string(),
                    鍵: 鍵.clone(),
                }))
            }
        }
    }
}
