//! 圧縮前のHDR画像: 明るさの圧縮とsRGB符号化を通す前の単精度の画素と、その寸法を所有する値オブジェクト。
//!
//! 8ビットの`読み戻し画像`と別の型にするのは、1画素のバイト数も1成分の型も違うためである。同じ型で扱うと、
//! バイト長の検算がどちらの形式のものか決まらず、片方の形式の絵をもう片方として読んでも構築が通ってしまう。
//!
//! 成分の並べ方(RGBAの4成分を単精度リトルエンディアンで先頭から、行を上から順に)を知るのはこの型だけである。
//! 実測ではこの読み手が`hdr_luminance`と`local_visibility`と`ibl_step`で3回書き直されていた。
//!
//! 構築の口をすべて`検証して組み立てる`へ通すのは、寸法と成分の数が合っていることをこの型の不変条件に
//! するためである。読み込みの工程は`load`が、試験のための構築は`test_support`が持つ。

mod load;
#[cfg(test)]
mod test_support;

use super::error::検収エラー;
use super::pixel_geometry::{画像の幅, 画像の高さ, 画素の番号};
use super::readback_dump::読み戻しの書き出し先;

/// 1画素あたりの成分数。RGBAの4つである。
const 画素あたりの成分数: usize = 4;

/// 注意: 幅と高さと成分の数の関係(`成分列.len() == 幅 * 高さ * 4`)がこの型の不変条件である。
pub struct 圧縮前のHDR画像 {
    幅: 画像の幅,
    高さ: 画像の高さ,
    成分列: Vec<f32>,
}

impl 圧縮前のHDR画像 {
    /// 書き出し先の対の2ファイルから読み込む。寸法と成分の数が食い違えば、絵を判定する前にここで落とす。
    pub fn 読み込む(書き出し先: &読み戻しの書き出し先) -> Result<Self, 検収エラー> {
        load::対の2ファイルから読み込む(書き出し先)
    }

    /// この型を作る唯一の口。寸法を数で受けるのはここが境界だからである。
    fn 検証して組み立てる(幅: usize, 高さ: usize, 成分列: Vec<f32>) -> Result<Self, 検収エラー> {
        let 寸法から求めた成分数 = 幅
            .checked_mul(高さ)
            .and_then(|画素数| 画素数.checked_mul(画素あたりの成分数))
            .ok_or(検収エラー::読み戻しの寸法がバイト長へ収まらない { 幅, 高さ })?;
        if 成分列.len() != 寸法から求めた成分数 {
            return Err(検収エラー::読み戻しの寸法とバイト長が食い違う {
                寸法から求めたバイト長: 寸法から求めた成分数,
                実際のバイト長: 成分列.len(),
            });
        }
        Ok(Self {
            幅: 画像の幅::生成する(幅),
            高さ: 画像の高さ::生成する(高さ),
            成分列,
        })
    }

    pub fn 画素数(&self) -> usize {
        self.幅.画素数() * self.高さ.画素数()
    }

    pub fn 画素数が同じか(&self, 相手: &Self) -> bool {
        self.画素数() == 相手.画素数()
    }

    /// 2枚の成分がビット単位で同じか。バイト一致を見る判定がこれを使う。
    ///
    /// 等値でなくビットで比べるのは、非数どうしが等値では一致と判定されないためである。
    /// 書き出されたファイルのバイト一致を見たい判定に、非数の有無で結果が変わる比較を渡さない。
    pub fn 成分がビット単位で同じか(&self, 相手: &Self) -> bool {
        self.成分列.len() == 相手.成分列.len() && self.成分列.iter().zip(&相手.成分列).all(|(左, 右)| 左.to_bits() == 右.to_bits())
    }

    /// 先頭から数えた画素のRGB。透過の成分は判定が1つも読まないため返さない。
    ///
    /// 注意: 画素数以上の番号を渡すことは呼び出し側のバグであるため、そのときは破れた不変条件を名指しして落とす。
    pub fn 番号の画素(&self, 番号: 画素の番号) -> [f32; 3] {
        assert!(
            番号.値() < self.画素数(),
            "圧縮前のHDR画像({}画素)の外の画素(番号{})を読もうとした",
            self.画素数(),
            番号.値()
        );
        let 先頭 = 番号.値() * 画素あたりの成分数;
        [self.成分列[先頭], self.成分列[先頭 + 1], self.成分列[先頭 + 2]]
    }

    /// 画素を4成分ずつ先頭から並べた並び。全画素を順に見る集計がこれを使う。
    pub fn 画素列(&self) -> impl Iterator<Item = &[f32]> {
        self.成分列.chunks_exact(画素あたりの成分数)
    }

    /// 先頭から数えた画素の番号の並び。2枚を同じ順で突き合わせる判定がこれを使う。
    pub fn 画素の番号一覧(&self) -> impl Iterator<Item = 画素の番号> {
        (0..self.画素数()).map(画素の番号::生成する)
    }
}
