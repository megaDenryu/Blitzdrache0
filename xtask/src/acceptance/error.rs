//! 検収の共通語彙が返す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。
//! この様式をここが1つ持ち、以後xtaskへ足す誤りの型はこの形に倣う。
//!
//! `String`への変換を1つ置くのは、既存の入口が`Result<_, String>`を返すためである。
//! 呼び出し側に`map_err`を書かせず、生の文へ戻る場所をこの1箇所へ閉じる。
//! 既存の入口が型付きエラーへ移り終えたらこの変換は消える(構造是正計画の順2の第2工程)。

mod display;
mod readback_break;

use std::path::PathBuf;

pub use readback_break::読み戻しの破れ;

use super::run_name::検収の実行名;
use crate::report_heading::報告の見出し;

#[derive(Debug)]
pub enum 検収エラー {
    出力ディレクトリを作れなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    アプリを起こせなかった {
        実行名: 検収の実行名,
        起こし方: &'static str,
        誤り: std::io::Error,
    },
    アプリが失敗して終わった {
        実行名: 検収の実行名,
        終了状態: String,
    },
    検証層の指摘が残った {
        実行名: 検収の実行名,
        件数: u64,
    },
    報告に見出しの行が無い {
        実行名: 検収の実行名,
        見出し: 報告の見出し,
    },
    報告の値を数として読めない {
        実行名: 検収の実行名,
        見出し: 報告の見出し,
        本文: String,
    },
    /// 書き出されたファイルを絵として読む段の破れ。7つの前提を`読み戻しの破れ`が数え上げる。
    読み戻しが破れた(読み戻しの破れ),
    /// 型が組み立てる構造用の選択肢を、汎用の口から積んだ。型で固定したシーンや枚数や書き出し先を
    /// 上書き・重複できてしまうため、起動の組み立ての時点で落とす。
    予約された選択肢を汎用の口から積んだ {
        綴り: String,
        予約の一覧: String,
    },
    検収の実行名が空である,
    検収の実行名が使えない文字を含む {
        名前: String,
        文字: char,
    },
    検収の実行名が予約された装置の名前である {
        名前: String,
    },
    /// 理由を文で持つのは、変換が外部のツールの起動であり、失敗の種類をこちらで数え上げられないためである。
    /// 変換の工程が型付きエラーへ移れば、この枝はその型を持つ。
    目視用の絵へ変換できなかった {
        書き出し先: PathBuf,
        理由: String,
    },
}

impl std::error::Error for 検収エラー {}

/// 生の文へ戻る唯一の境界。`Result<_, String>`を返す既存の入口が`?`でそのまま受けられるようにする。
impl From<検収エラー> for String {
    fn from(誤り: 検収エラー) -> Self {
        誤り.to_string()
    }
}
