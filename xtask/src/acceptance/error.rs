//! 検収の共通語彙が返す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。
//! この様式をここが1つ持ち、以後xtaskへ足す誤りの型はこの形に倣う。
//!
//! 生の文へ戻る変換をこの型が持たないのは、検収の入口がすべて型付きエラーへ移り終えたためである。
//! 人が読む1文になるのは、入口の`実行する`が終了コードへ写す1箇所だけである。
//!
//! `予約された選択肢を汎用の口から積んだ`は、型が組み立てる構造用の選択肢を汎用の口から積んだ枝である。
//! 型で固定したシーンや枚数や書き出し先を上書き・重複できてしまうため、起動の組み立ての時点で落とす。

mod display;
mod judgment_break;
mod ratio_break;
mod readback_break;
mod report_read_break;

use std::path::PathBuf;

pub use judgment_break::{判定の破れ, 判定の破れの種類};
pub use ratio_break::割合の破れ;
pub use readback_break::読み戻しの破れ;
pub use report_read_break::報告の読み取りの破れ;

use super::run_name::検収の実行名;
use crate::raw_png::目視用の絵への変換の破れ;

#[derive(Debug)]
pub enum 検収エラー {
    出力ディレクトリを作れなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    アプリを起こせなかった {
        実行名: 検収の実行名,
        起こし方: &'static str,
        誤り: std::io::Error,
    },
    アプリが失敗して終わった {
        実行名: 検収の実行名,
        終了状態: String,
    },
    検証層の指摘が残った {
        実行名: 検収の実行名,
        件数: u64,
    },
    報告の読み取りが破れた {
        実行名: 検収の実行名,
        破れ: 報告の読み取りの破れ,
    }, // 終了時報告から数を取り出す段の破れ
    読み戻しが破れた(読み戻しの破れ), // 書き出されたファイルを絵として読む段の破れ
    判定が破れた(判定の破れ),         // 絵と報告から採った数へ課した判定の破れ
    予約された選択肢を汎用の口から積んだ {
        綴り: String,
        予約の一覧: String,
    }, // 型が組み立てる構造用の選択肢を汎用の口から積んだ
    割合が破れた(割合の破れ),         // 画素の数どうしの比を求める段の破れ
    検収の実行名が空である,
    検収の実行名が使えない文字を含む {
        名前: String,
        文字: char,
    },
    検収の実行名が予約された装置の名前である {
        名前: String,
    },
    目視用の絵へ変換できなかった {
        書き出し先: PathBuf,
        破れ: 目視用の絵への変換の破れ,
    }, // 生バイト列をPNGへ写す段の破れ
}

impl std::error::Error for 検収エラー {}

/// 判定の破れを検収エラーへ載せる境界。判定の側は自分が検収の一部であることを知らずに破れだけを返す。
impl From<判定の破れ> for 検収エラー {
    fn from(破れ: 判定の破れ) -> Self {
        Self::判定が破れた(破れ)
    }
}
