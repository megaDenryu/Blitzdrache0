//! 読み戻し画像: アプリが書き出した最終フレームのRGBA8と、その寸法を所有する値オブジェクト。
//!
//! バイト列の並べ方を知るのはこの型だけである。寸法とバイト列を裸で配ると、消費側がそれぞれ
//! `(y * 幅 + x) * 4`を書き直すことになり、実測ではその写しが10箇所へ散っていた。
//! 添字の組み立てが散ると、書き出しの並びが変わったときに直し漏れた入口だけが静かに別の画素を読む。
//!
//! 構築の口を読み込みだけにするのは、寸法とバイト長が合っていることをこの型の不変条件にするためである。
//! 合っていない値でも構築できると、範囲内の座標を渡したのに範囲外を読む状態が作れてしまう。
//! 読み込みの工程は`load`が持つ。

mod load;
#[cfg(test)]
mod test_support;

use super::error::検収エラー;
use super::readback_dump::読み戻しの書き出し先;

/// 注意: 幅と高さとバイト長の関係(`rgba8.len() == 幅 * 高さ * 4`)がこの型の不変条件である。
/// 構築は`読み込む`だけを通し、この不変条件が破れた値を作らせない。
pub struct 読み戻し画像 {
    幅: usize,
    高さ: usize,
    rgba8: Vec<u8>,
}

impl 読み戻し画像 {
    /// 書き出し先の対の2ファイルから読み込む。寸法とバイト長が食い違えば、絵を判定する前にここで落とす。
    pub fn 読み込む(書き出し先: &読み戻しの書き出し先) -> Result<Self, 検収エラー> {
        load::対の2ファイルから読み込む(書き出し先)
    }

    pub fn 幅(&self) -> usize {
        self.幅
    }

    pub fn 高さ(&self) -> usize {
        self.高さ
    }

    pub fn 画素数(&self) -> usize {
        self.幅 * self.高さ
    }

    /// 位置の画素のRGB。
    ///
    /// 注意: 範囲外の座標を渡すことは呼び出し側のバグであるため、そのときは破れた不変条件を名指しして落とす。
    pub fn 座標の画素(&self, x: usize, y: usize) -> [u8; 3] {
        assert!(
            x < self.幅 && y < self.高さ,
            "読み戻し画像({}×{})の外の画素({x}, {y})を読もうとした",
            self.幅,
            self.高さ
        );
        self.添字の画素(y * self.幅 + x)
    }

    /// 先頭から数えた画素のRGB。走査の順序だけが要る判定は座標を組み立てずにこちらで読む。
    ///
    /// 注意: 画素数以上の添字を渡すことは呼び出し側のバグであるため、そのときは破れた不変条件を名指しして落とす。
    pub fn 添字の画素(&self, 添字: usize) -> [u8; 3] {
        assert!(
            添字 < self.画素数(),
            "読み戻し画像({}画素)の外の画素(添字{添字})を読もうとした",
            self.画素数()
        );
        let 先頭 = 添字 * 4;
        [self.rgba8[先頭], self.rgba8[先頭 + 1], self.rgba8[先頭 + 2]]
    }

    /// 画素を4バイトずつ先頭から並べた並び。全画素を順に見る判定がこれを使う。
    pub fn 画素列(&self) -> impl Iterator<Item = &[u8]> {
        self.rgba8.chunks_exact(4)
    }

    /// RGBA8の連結そのもの。2枚のバイト一致を見る判定と、書き出しへ渡す境界だけが読む。
    pub fn バイト列(&self) -> &[u8] {
        &self.rgba8
    }

    /// その行の先頭から末尾までのバイト列。画面を上下に切って片側だけのバイト一致を見る判定が読む。
    ///
    /// 注意: 高さ以上の行を渡すことは呼び出し側のバグであるため、そのときは破れた不変条件を名指しして落とす。
    pub fn 行以降のバイト列(&self, y: usize) -> &[u8] {
        assert!(y <= self.高さ, "読み戻し画像(高さ{})の外の行{y}を読もうとした", self.高さ);
        &self.rgba8[y * self.幅 * 4..]
    }

    pub fn 寸法が同じか(&self, 相手: &Self) -> bool {
        self.幅 == 相手.幅 && self.高さ == 相手.高さ
    }

    /// 誤りの文面へ埋める寸法の綴り。2枚の寸法が違うことを言う判定がこれを使う。
    pub fn 寸法の綴り(&self) -> String {
        format!("{}×{}", self.幅, self.高さ)
    }
}
