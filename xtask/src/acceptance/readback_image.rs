//! 読み戻し画像: アプリが書き出した最終フレームのRGBA8と、その寸法を所有する値オブジェクト。
//!
//! 寸法は次元ごとの型のまま保持する。数で持って読み出しのたびに包み直すと、型が入口と出口の飾りになり、
//! 内側では取り違えが起こりうる状態に戻る。
//!
//! バイト列の並べ方を知るのはこの型だけである。寸法とバイト列を裸で配ると、消費側がそれぞれ
//! `(y * 幅 + x) * 4`を書き直すことになり、実測ではその写しが10箇所へ散っていた。
//! 添字の組み立てが散ると、書き出しの並びが変わったときに直し漏れた入口だけが静かに別の画素を読む。
//!
//! 構築の口をすべて`検証して組み立てる`へ通すのは、寸法とバイト長が合っていることをこの型の不変条件に
//! するためである。合っていない値でも構築できると、範囲内の座標を渡したのに範囲外を読む状態が作れてしまう。
//! 試験のための構築も同じ口を通す。試験だけが不変条件を破れると、破れた絵で通した判定の結果が
//! 本番の絵での結果と対応しなくなる。
//! 読み込みの工程は`load`が、バイト列の並べ方を知る読み出しは`pixel_access`が、
//! 不変条件の回帰検査は`invariant_tests`が持つ。明るさの圧縮を通す前の単精度の読み戻しは
//! `readback_hdr_image`が別に持つ。1成分の型もバイト数も違うため、同じ型で扱うと長さの検算が
//! どちらの形式のものか決まらない。

#[cfg(test)]
mod invariant_tests;
mod load;
mod pixel_access;
#[cfg(test)]
mod test_support;

use super::error::{検収エラー, 読み戻しの破れ};
use super::pixel_geometry::{画像の幅, 画像の高さ};
use super::readback_dump::読み戻しの書き出し先;

/// 1画素あたりのバイト数。書き出しはRGBA8の連結であり、寸法からバイト長を求めるのにこの数を掛ける。
const 画素あたりのバイト数: usize = 4;

/// 注意: 幅と高さとバイト長の関係(`rgba8.len() == 幅 * 高さ * 4`)がこの型の不変条件である。
/// 構築は`検証して組み立てる`だけを通し、この不変条件が破れた値を作らせない。
pub struct 読み戻し画像 {
    幅: 画像の幅,
    高さ: 画像の高さ,
    rgba8: Vec<u8>,
}

impl 読み戻し画像 {
    /// 書き出し先の対の2ファイルから読み込む。寸法とバイト長が食い違えば、絵を判定する前にここで落とす。
    pub fn 読み込む(書き出し先: &読み戻しの書き出し先) -> Result<Self, 検収エラー> {
        load::対の2ファイルから読み込む(書き出し先)
    }

    /// この型を作る唯一の口。不変条件を確かめ、破れていれば型付きエラーで返す。
    /// 読み込みも試験用の合成もここを通るため、不変条件を破った値はどの経路からも作れない。
    ///
    /// 寸法を数で受けるのはここが境界だからである。書き出された寸法のファイルも試験の合成も
    /// 数の対を持ち込むため、次元の型を着せるのはこの1箇所であり、以後は型のまま保つ。
    fn 検証して組み立てる(幅: usize, 高さ: usize, rgba8: Vec<u8>) -> Result<Self, 検収エラー> {
        let 寸法から求めたバイト長 =
            幅.checked_mul(高さ)
                .and_then(|画素数| 画素数.checked_mul(画素あたりのバイト数))
                .ok_or(検収エラー::読み戻しが破れた(
                    読み戻しの破れ::寸法がバイト長へ収まらない { 幅, 高さ },
                ))?;
        if rgba8.len() != 寸法から求めたバイト長 {
            return Err(検収エラー::読み戻しが破れた(
                読み戻しの破れ::寸法とバイト長が食い違う {
                    寸法から求めたバイト長,
                    実際のバイト長: rgba8.len(),
                },
            ));
        }
        Ok(Self {
            幅: 画像の幅::生成する(幅),
            高さ: 画像の高さ::生成する(高さ),
            rgba8,
        })
    }

    pub fn 幅(&self) -> 画像の幅 {
        self.幅
    }

    pub fn 高さ(&self) -> 画像の高さ {
        self.高さ
    }

    pub fn 画素数(&self) -> usize {
        self.幅.画素数() * self.高さ.画素数()
    }

    pub fn 寸法が同じか(&self, 相手: &Self) -> bool {
        self.幅 == 相手.幅 && self.高さ == 相手.高さ
    }

    /// 誤りの文面へ埋める寸法の綴り。2枚の寸法が違うことを言う判定がこれを使う。
    pub fn 寸法の綴り(&self) -> String {
        format!("{}×{}", self.幅.画素数(), self.高さ.画素数())
    }
}
