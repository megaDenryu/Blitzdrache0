//! 予約された選択肢: 型が組み立てる構造用の選択肢の文字列。汎用の口から積んでよいかの判定をここが1つ持つ。
//!
//! これが要るのは、汎用の口(`選択肢を足す`等)が`--scene`や`--frames`を積めてしまうと、型で固定したシーンや
//! 正のフレーム数や書き出し先を上書き・重複できるためである。値オブジェクトが不変条件を守っても、
//! 同じ選択肢を後から重ねられるなら守れていない。
//!
//! 文字列を写して並べないのは、写しが正本とずれるためである。文字列を持つ型(シーン・描き終わり・世界の置き場・
//! 書き出しの形式)からそれぞれ受け取って1つの並びにする。

use super::draw_end::描き終わりの決め方;
use super::dump_format::書き出しの形式;

/// その文字列が型の組み立てる選択肢か。汎用の口はこれが真の文字列を拒む。
pub(super) fn 予約された選択肢か(文字列: &str) -> bool {
    予約された選択肢の文字列一覧().into_iter().any(|予約| 予約 == 文字列)
}

/// 予約された選択肢の文字列の全部。失敗の文面が「何が予約されているか」を並べるためにも読む。
pub(super) fn 予約された選択肢の文字列一覧() -> Vec<&'static str> {
    let mut 一覧 = vec![super::launch_specification::シーンの選択肢の文字列, super::app_launch::読む世界の置き場の選択肢の文字列];
    一覧.extend(描き終わりの決め方::選択肢の文字列一覧());
    一覧.extend(書き出しの形式::選択肢の文字列一覧());
    一覧
}
