//! 書き出された寸法のファイルの読み取り。受け取るのは書き出し先、返すのは幅と高さの2数である。
//!
//! `.size`の本文の形(空白で区切った「幅 高さ」)を知るのはここだけである。8ビットの読み戻しと
//! 明るさの圧縮前の読み戻しが同じ形の寸法ファイルを持つため、読み方を2つに分けると、片方だけが
//! 書式の変更に追従しない状態が作れる。

#[cfg(test)]
mod parse_tests;

use super::error::検収エラー;
use super::readback_dump::読み戻しの書き出し先;

/// 寸法のファイルは「幅 高さ」の2数だけを持つ。
///
/// 注意: 数として読めない語を捨ててはならない。捨てると「1920 壊れた語 1080」が1920×1080として通り、
/// 書き出しが壊れた実行の絵をそのまま判定してしまう。語は1つ残らず数として読み、ちょうど2語であることを求める。
pub(super) fn 幅と高さを読む(書き出し先: &読み戻しの書き出し先) -> Result<(usize, usize), 検収エラー> {
    let 寸法のパス = 書き出し先.寸法のパス();
    let 本文 = std::fs::read_to_string(&寸法のパス).map_err(|誤り| 検収エラー::読み戻しのファイルを読めない {
        パス: 寸法のパス.clone(),
        誤り,
    })?;
    幅と高さの2数を解く(&本文).ok_or(検収エラー::読み戻しの寸法が幅と高さの2数でない {
        パス: 寸法のパス, 本文
    })
}

/// 本文を空白で区切り、ちょうど2語がどちらも数であるときだけ幅と高さを返す。
pub(super) fn 幅と高さの2数を解く(本文: &str) -> Option<(usize, usize)> {
    let 数一覧 = 本文.split_whitespace().map(str::parse::<usize>).collect::<Result<Vec<usize>, _>>().ok()?;
    match 数一覧[..] {
        [幅, 高さ] => Some((幅, 高さ)),
        _ => None,
    }
}
