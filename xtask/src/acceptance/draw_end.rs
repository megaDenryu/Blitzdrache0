//! 描き終わりの決め方: その起動がどこで描き終わるか。
//!
//! 枚数を`Option`で持たないのは、無しが「枚数を決めていない」と「終わりを決めていない」のどちらを指すかが
//! 型から決まらないためである。終わり方そのものを選択肢で数え上げ、アプリへ渡す選択肢の文字列もこの型が持つ。

use std::ffi::OsString;

use super::frame_count::描画フレーム数;

pub(super) enum 描き終わりの決め方 {
    枚数を描き切る(描画フレーム数),       // 決めた枚数を描いたら終わる。絵を読む検収はすべてこれ
    計測の枚数を描き切る(描画フレーム数), // 決めた枚数を計測窓として描いたら終わる。自己操作を入れずに費用を測る実行がこれ
    人が終えるまで描き続ける,             // 人が画面を閉じるまで描き続ける。遊ぶ入口だけがこれ
}

/// 枚数をアプリへ渡す選択肢の文字列。生の文字列が在るのはこの2行だけである。
const 枚数の選択肢の文字列: &str = "--frames";
const 計測の枚数の選択肢の文字列: &str = "--benchmark-frames";

impl 描き終わりの決め方 {
    /// この型が組み立てる選択肢の文字列。汎用の口が同じ文字列を積むことを拒むために読まれる。
    pub(super) fn 選択肢の文字列一覧() -> [&'static str; 2] {
        [枚数の選択肢の文字列, 計測の枚数の選択肢の文字列]
    }

    pub(super) fn 引数列へ足す(&self, 並び: &mut Vec<OsString>) {
        let (文字列, フレーム数) = match self {
            Self::枚数を描き切る(フレーム数) => (枚数の選択肢の文字列, フレーム数),
            Self::計測の枚数を描き切る(フレーム数) => (計測の枚数の選択肢の文字列, フレーム数),
            Self::人が終えるまで描き続ける => return,
        };
        並び.push(OsString::from(文字列));
        並び.push(OsString::from(フレーム数.文字列()));
    }
}
