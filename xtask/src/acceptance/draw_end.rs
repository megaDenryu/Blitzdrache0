//! 描き終わりの決め方: その起動がどこで描き終わるか。
//!
//! 枚数を`Option`で持たないのは、無しが「枚数を決めていない」と「終わりを決めていない」のどちらを指すかが
//! 型から決まらないためである。終わり方そのものを枝で数え上げ、アプリへ渡す選択肢の綴りもこの型が持つ。

use std::process::Command;

use super::frame_count::描画フレーム数;

pub(super) enum 描き終わりの決め方 {
    /// 決めた枚数を描いたら終わる。絵を読む検収はすべてこれである。
    枚数を描き切る(描画フレーム数),
    /// 決めた枚数を計測窓として描いたら終わる。自己操作を1つも入れずに費用を測る実行がこれである。
    計測の枚数を描き切る(描画フレーム数),
    /// 人が画面を閉じるまで描き続ける。遊ぶ入口だけがこれである。
    人が終えるまで描き続ける,
}

impl 描き終わりの決め方 {
    pub(super) fn コマンドへ並べる(&self, コマンド: &mut Command) {
        match self {
            Self::枚数を描き切る(フレーム数) => {
                コマンド.args(["--frames", &フレーム数.綴り()]);
            }
            Self::計測の枚数を描き切る(フレーム数) => {
                コマンド.args(["--benchmark-frames", &フレーム数.綴り()]);
            }
            Self::人が終えるまで描き続ける => {}
        }
    }
}
