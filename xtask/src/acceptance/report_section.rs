//! 報告の区画: 見出しの行に続く、見出しより深く字下げされた行の並びを所有する型。
//!
//! 区画で切ってから行を探すのは、同じ綴りの行が複数の報告に現れるためである。行の綴りだけで報告全体を探すと、
//! 別の報告の値を読んだまま成功する。実測では分位の行がその形で衝突していた。
//!
//! 見出しを一緒に持つのは、区画の中に探した行が無かったときの文面が「どの区画を見たか」を言うためである。

use super::error::{報告の読み取りの破れ, 検収エラー};
use super::report_line::報告の行;
use super::run_name::検収の実行名;
use crate::report_heading::報告の見出し;

pub struct 報告の区画 {
    実行名: 検収の実行名,
    見出し: 報告の見出し,
    行一覧: Vec<報告の行>,
}

impl 報告の区画 {
    pub(super) fn 切り出す(実行名: &検収の実行名, 見出し: 報告の見出し, 標準出力: &str) -> Result<Self, 検収エラー> {
        let mut 残り = 標準出力.lines().skip_while(|行| !見出し.行の始まりか(行));
        let Some(見出し行) = 残り.next() else {
            return Err(検収エラー::報告の読み取りが破れた {
                実行名: 実行名.clone(),
                破れ: 報告の読み取りの破れ::見出しの行が無い { 見出し },
            });
        };
        let 見出しの深さ = 字下げの深さ(見出し行);
        let 行一覧 = 残り
            .take_while(|行| 字下げの深さ(行) > 見出しの深さ && !行.trim().is_empty())
            .map(|行| 報告の行::取り込む(実行名, 行))
            .collect();
        Ok(Self {
            実行名: 実行名.clone(),
            見出し,
            行一覧,
        })
    }

    /// 区画の中で、指定した接頭辞で始まる最初の行。
    pub fn 接頭辞の行(&self, 接頭辞: &報告の見出し) -> Result<&報告の行, 検収エラー> {
        self.行一覧
            .iter()
            .find(|行| 接頭辞.行の始まりか(行.原文()))
            .ok_or_else(|| 検収エラー::報告の読み取りが破れた {
                実行名: self.実行名.clone(),
                破れ: 報告の読み取りの破れ::区画に接頭辞の行が無い {
                    見出し: self.見出し.clone(),
                    接頭辞: 接頭辞.clone(),
                },
            })
    }

    /// 区画に並ぶ行の全部。行の本数を数える判定と、表として1行ずつ写し取る読み取りがこれを使う。
    pub fn 行一覧(&self) -> &[報告の行] {
        &self.行一覧
    }
}

fn 字下げの深さ(行: &str) -> usize {
    行.len() - 行.trim_start().len()
}
