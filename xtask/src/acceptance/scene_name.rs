//! 検収シーン名: アプリへ渡すシーンの名前。プロセス境界の文字列であり、文字列の正本はアプリの世界の宣言が持つ。
//!
//! 世界名のように選択肢で数え上げないのは、シーンの一覧がアプリの側にしか無く、xtaskがそれを型として持てないためである。
//! 数え上げは構造是正計画の順3(blitz_appのシーン名の判別共用体化)が作り、そこができたらこの型はその選択肢を包む。
//! それまでの下支えとして、プロセス境界の1語として成立することだけを構築時に確かめる。

#[repr(transparent)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 検収シーン名(&'static str);

impl 検収シーン名 {
    /// 注意: 空の文字列と空白を含む文字列は、コマンドの引数として1語にならず別の引数と混ざる。
    /// 文字列は原文のリテラルであるため、破れは書き誤りであり、定数として使う限りコンパイル時に落ちる。
    pub const fn 生成する(文字列: &'static str) -> Self {
        assert!(!文字列.is_empty(), "検収シーン名が空である");
        let バイト列 = 文字列.as_bytes();
        let mut 位置 = 0;
        while 位置 < バイト列.len() {
            assert!(!バイト列[位置].is_ascii_whitespace(), "検収シーン名が空白を含む");
            位置 += 1;
        }
        Self(文字列)
    }

    /// アプリの`--scene`へ渡す文字列。生の文字列へ戻るのはここだけである。
    pub(crate) fn 文字列(self) -> &'static str {
        self.0
    }
}
