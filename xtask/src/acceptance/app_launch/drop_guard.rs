//! アプリの起動の閉じ忘れの検出。触れるのは`終了済みか`と`実行名`だけであり、コマンドには触れない。
//!
//! `#[must_use]`だけでは足りないのは、その注記が「戻り値を捨てた」ことしか捕まえないためである。
//! 変数へ受けて引数を積んだ後、終端メソッドを呼ばずスコープを抜ける形はそのまま通る。
//! 終端メソッドだけが終了済みへ遷移し、未終了のまま捨てられたことをここが落とす。
//!
//! 回復可能な失敗でなくpanicにするのは、これが到達したらプログラムのバグだからである。積むだけ積んで
//! 走らせない起動は、その入口が検収を1つも行わずに成功を返している状態であり、返す先が無い。

use super::アプリの起動;

impl Drop for アプリの起動 {
    fn drop(&mut self) {
        assert!(
            self.終了済みか,
            "アプリの起動({})を終端メソッド(走らせて終了時報告を得る・画面へ流したまま走らせて終わりを待つ)を呼ばずに捨てた",
            self.実行名
        );
    }
}
