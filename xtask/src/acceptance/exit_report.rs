//! 終了時報告: アプリが終わりぎわに書いた標準出力と標準エラーを所有し、その読み取りをメソッドで見せる型。
//!
//! 本文を裸の`&str`で配ると、受け取った側がそれぞれの流儀で行を探して数を読む。実測では、その署名が
//! 76箇所へ流れており、報告のどの行を誰が読んでいるのかを本文の型からは1つも辿れなかった。
//!
//! 標準エラーも一緒に持つのは、検証層の指摘がそちらへ出るためである。標準出力だけを持つと、判定が落ちた入口が
//! 「なぜ落ちたか」を書いた行を捨てたまま失敗を返す。
//!
//! 実行名を一緒に持つのは、失敗の文面が「どの実行の報告か」を必ず言うためである。
//! 名前をメソッドの引数で毎回受けると、渡し忘れた入口だけが名無しの失敗を出す。
//! 綴りへ剥がさず型のまま持つのは、この報告を読む側が実行名としての決め事を保ったまま受け取るためである。

use super::error::検収エラー;
use super::run_name::検収の実行名;
use crate::report_heading::報告の見出し;
use crate::validation_count::検証層の指摘件数の見出し;

pub struct 終了時報告 {
    実行名: 検収の実行名,
    標準出力: String,
    標準エラー: String,
}

impl 終了時報告 {
    pub fn 取り込む(実行名: &検収の実行名, 標準出力: String, 標準エラー: String) -> Self {
        Self {
            実行名: 実行名.clone(),
            標準出力,
            標準エラー,
        }
    }

    /// 検証層の指摘が1件も無いことを確かめる。絵を判定する前に、絵の正しさの前提が崩れていないかを見る。
    pub fn 検証層の指摘が零件であることを確かめる(&self) -> Result<(), 検収エラー> {
        let 件数 = self.検証層の指摘件数()?;
        if 件数 == 0 {
            return Ok(());
        }
        Err(検収エラー::検証層の指摘が残った {
            実行名: self.実行名.clone(),
            件数,
        })
    }

    pub fn 検証層の指摘件数(&self) -> Result<u64, 検収エラー> {
        self.見出しに続く数(検証層の指摘件数の見出し)
    }

    /// 見出しで始まる最初の行。無いことを失敗と読み替えず、無いことを返す。
    pub fn 見出しの行(&self, 見出し: 報告の見出し) -> Option<&str> {
        見出し.行を探す(&self.標準出力)
    }

    /// 見出しに続く本文を数として読む。行が無いことと数として読めないことを別の枝で返す。
    pub fn 見出しに続く数(&self, 見出し: 報告の見出し) -> Result<u64, 検収エラー> {
        let 行 = self.見出しの行(見出し).ok_or_else(|| 検収エラー::報告に見出しの行が無い {
            実行名: self.実行名.clone(),
            見出し,
        })?;
        let 本文 = 見出し.見出しに続く本文(行);
        本文.parse().map_err(|_| 検収エラー::報告の値を数として読めない {
            実行名: self.実行名.clone(),
            見出し,
            本文: 本文.to_string(),
        })
    }

    /// 報告をそのまま画面へ流す。失敗した実行の中身を人が見るための口である。
    pub fn 画面へ流す(&self) {
        print!("{}", self.標準出力);
    }

    /// 標準エラーをそのまま画面へ流す。検証層の指摘を人が見るための口である。
    pub fn 標準エラーを画面へ流す(&self) {
        eprint!("{}", self.標準エラー);
    }

    /// 標準エラーそのもの。失敗の文面へ埋める工程が受け取る口である。
    pub fn 標準エラーの本文(&self) -> &str {
        &self.標準エラー
    }

    /// 標準出力そのもの。行の綴りをまだ型で持てていない読み取りの工程が受け取る唯一の口である。
    /// 構造是正計画の順2の第2工程で、これらの工程がこの型のメソッドへ移ると消える。
    pub fn 本文(&self) -> &str {
        &self.標準出力
    }
}
