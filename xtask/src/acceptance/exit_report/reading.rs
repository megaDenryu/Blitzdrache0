//! 終了時報告の標準出力からの読み取り。触れるのは標準出力と実行名だけであり、標準エラーには触れない。
//!
//! 検収が報告から数を採る経路をここへ集めるのは、どの入口も同じ3つの形(見出しの行・見出しの区画・
//! 同じ見出しで始まる行の全部)しか使わないためである。実測ではその3形が61の入口で別々に書かれており、
//! 字下げの扱いと数の読み方が入口ごとに違っていた。
//!
//! 破れは実行名を添えて返す。どの実行の報告を読んで落ちたのかを、受け取る側が組み立て直さずに言えるようにする。

use super::終了時報告;
use crate::acceptance::error::{報告の読み取りの破れ, 検収エラー};
use crate::acceptance::report_line::報告の行;
use crate::acceptance::report_section::報告の区画;
use crate::report_heading::報告の見出し;

impl 終了時報告 {
    /// 見出しで始まる最初の行。無いことを失敗と読み替えず、無いことを返す。
    pub fn 見出しの行(&self, 見出し: &報告の見出し) -> Option<&str> {
        見出し.行を探す(&self.標準出力)
    }

    /// 見出しで始まる最初の行を型のまま取り出す。行の中の値を鍵で読む工程がこの口を通る。
    pub fn 見出しの1行(&self, 見出し: &報告の見出し) -> Result<報告の行, 検収エラー> {
        Ok(報告の行::取り込む(&self.実行名, self.見出しの行を求める(見出し)?.trim_end()))
    }

    /// 見出しで始まる行の全部。同じ綴りの行が何本出たかを見る判定がこれを使う。
    pub fn 見出しで始まる行の一覧(&self, 見出し: &報告の見出し) -> Vec<報告の行> {
        self.標準出力
            .lines()
            .filter(|行| 見出し.行の始まりか(行))
            .map(|行| 報告の行::取り込む(&self.実行名, 行.trim_end()))
            .collect()
    }

    /// いずれかの見出しで始まる行の全部を、報告に出た順で。種類の違う事象を起きた順に並べて読む工程がこれを使う。
    /// 見出しごとに読むと種類をまたいだ前後関係が消えるため、1回の走査で拾う口をここに置く。
    pub fn いずれかの見出しで始まる行の一覧(&self, 見出し一覧: &[報告の見出し]) -> Vec<報告の行> {
        self.標準出力
            .lines()
            .filter(|行| 見出し一覧.iter().any(|見出し| 見出し.行の始まりか(行)))
            .map(|行| 報告の行::取り込む(&self.実行名, 行.trim()))
            .collect()
    }

    /// 見出しの行に続く、見出しより深く字下げされた行の並び。
    pub fn 見出しの区画(&self, 見出し: 報告の見出し) -> Result<報告の区画, 検収エラー> {
        報告の区画::切り出す(&self.実行名, 見出し, &self.標準出力)
    }

    /// 見出しに続く本文を数として読む。行が無いことと数として読めないことを別の枝で返す。
    pub fn 見出しに続く数(&self, 見出し: &報告の見出し) -> Result<u64, 検収エラー> {
        let 本文 = self.見出しに続く本文(見出し)?;
        本文.parse().map_err(|_| {
            self.読み取りの破れ(報告の読み取りの破れ::見出しに続く本文を数として読めない {
                見出し: 見出し.clone(),
                本文: 本文.to_string(),
            })
        })
    }

    /// 「見出し: 0=9 1=6」の形で見出しに続く、添字順に並ぶ数の一覧。
    pub fn 見出しに続く添字順の数一覧<数: std::str::FromStr>(
        &self, 見出し: &報告の見出し
    ) -> Result<Vec<数>, 検収エラー> {
        self.見出しの1行(見出し)?.見出しに続く添字順の数一覧(見出し)
    }

    /// 見出しに続く本文。数でも添字の並びでもない形で並ぶ値を読む工程がこの口を通る。
    pub fn 見出しに続く本文(&self, 見出し: &報告の見出し) -> Result<&str, 検収エラー> {
        Ok(見出し.見出しに続く本文(self.見出しの行を求める(見出し)?))
    }

    fn 見出しの行を求める(&self, 見出し: &報告の見出し) -> Result<&str, 検収エラー> {
        self.見出しの行(見出し).ok_or_else(|| {
            self.読み取りの破れ(報告の読み取りの破れ::見出しの行が無い {
                見出し: 見出し.clone()
            })
        })
    }

    pub(super) fn 読み取りの破れ(&self, 破れ: 報告の読み取りの破れ) -> 検収エラー {
        検収エラー::報告の読み取りが破れた {
            実行名: self.実行名.clone(),
            破れ,
        }
    }
}
