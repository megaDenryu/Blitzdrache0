//! 「見出し: 0=9 1=6」の形で添字順に並ぶ数の一覧の読み取り。触れるのは標準出力と実行名だけである。
//!
//! 添字が0から1つずつ増えることを課すのは、飛んだ添字を詰めて読むと別の添字の値を返すためである。
//! 距離区分別やセット別の数はこの形で並び、添字がそのまま区分の番号を指す。
//!
//! 項が1つも無い実行はアプリが「なし」と綴るため、その綴りをこの型が知り、空の一覧として返す。

use super::終了時報告;
use crate::acceptance::error::{報告の読み取りの破れ, 検収エラー};
use crate::report_heading::報告の見出し;

/// 項が1つも無いことをアプリが綴る語。
const 項が無いことの綴り: &str = "なし";

impl 終了時報告 {
    pub fn 見出しに続く添字順の数一覧(&self, 見出し: &報告の見出し) -> Result<Vec<u64>, 検収エラー> {
        let 本文 = self.見出しに続く本文(見出し)?;
        if 本文 == 項が無いことの綴り {
            return Ok(Vec::new());
        }
        let mut 一覧 = Vec::new();
        for 項 in 本文.split_whitespace() {
            let (添字, 値) = 添字と値へ切る(self, 見出し, 項)?;
            if 一覧.len() != 添字 {
                return Err(self.読み取りの破れ(報告の読み取りの破れ::見出しに続く添字が0から昇順に並んでいない {
                    見出し: 見出し.clone(),
                    本文: 本文.to_string(),
                }));
            }
            一覧.push(値);
        }
        Ok(一覧)
    }
}

fn 添字と値へ切る(報告: &終了時報告, 見出し: &報告の見出し, 項: &str) -> Result<(usize, u64), 検収エラー> {
    let 対でない = || {
        報告.読み取りの破れ(報告の読み取りの破れ::見出しに続く項が添字と値の対でない {
            見出し: 見出し.clone(),
            項: 項.to_string(),
        })
    };
    let (添字, 値) = 項.split_once('=').ok_or_else(対でない)?;
    Ok((添字.parse().map_err(|_| 対でない())?, 値.parse().map_err(|_| 対でない())?))
}
