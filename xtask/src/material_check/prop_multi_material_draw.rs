//! マルチマテリアル段Eの検収入口。Blenderが生成した材質3つの小物を本番の描画経路へ通し、3つの材質が別々の色として
//! 画素に出ていること・描画発行がプリミティブの数だけ立つことを確かめて、目視用のPNGを書き出す。
//!
//! 材質の色を読む条件と本番の絵を採る条件を分ける。ライティングとポスト処理を切ると材質のベースカラーが画素へそのまま出るため、
//! 色の違いが材質の違いによるものだと言える。絵としての見た目は本番の経路から採り、その合否は親エージェントの目視が決める。
//! 1条件ぶんの起動と読み戻しは`run`、色の分布の採り方は`material_pixels`、画素の合否は`judgment`、計器の合否は`count_judgment`にある。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「段階導入」E段

mod count_judgment;
mod error;
mod judgment;
mod material_pixels;
mod run;

use std::process::ExitCode;

use crate::verify::{検証の出力のファイル名, 検証の出力の置き場名, 検証の出力ルート};
use error::小物の材質境界の検収エラー;

const 出力ディレクトリ: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("prop_multi_material_draw");
/// 小物の実行時形式。宣言はこの安定IDを板の世界へ載せるため、既定の出力ルートへ焼かれる。
const 実行時形式のファイル名: 検証の出力のファイル名 = 検証の出力のファイル名::生成する("prop_banded_chest.blitzasset");
/// アセットが宣言している材質の数。glbは材質スロットごとにプリミティブを分けるため、シーンパスの発行数もこの数になる。
const 材質の数: usize = 3;

pub fn 多材質小物の描画を確認する() -> ExitCode {
    match 検収する() {
        Ok(要約) => {
            println!("[xtask] prop-multi-material-draw成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] prop-multi-material-draw失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

fn 検収する() -> Result<String, 小物の材質境界の検収エラー> {
    if !crate::gen_source_assets::検証用ソースアセットを生成して成否を返す() || !crate::compile_assets::既定を生成する() {
        return Err(小物の材質境界の検収エラー::検証用アセットを生成できなかった);
    }
    実行時形式の実在を確かめる()?;
    let 実行環境 = run::実行環境を作る(検証の出力ルート::既定().名前が指す置き場(出力ディレクトリ))?;

    let 材質色 = 実行環境.描いて読み戻す(run::材質の色の実行名, &run::起動指定を組み立てる(run::条件::材質の色をそのまま読む))?;
    let 分布 = material_pixels::色の分布を採る(材質色.画像())?;
    let 画素判定 = judgment::材質の境界を検査する(&分布)?;
    let 計数 = crate::report_parse::取り出す(材質色.報告())?;
    count_judgment::検査する(&計数, 材質の数)?;
    let 平面png = 材質色.書き出し先().目視用の絵へ変換する()?;

    let 本番 = 実行環境.描いて読み戻す(run::本番経路の実行名, &run::起動指定を組み立てる(run::条件::本番経路))?;
    let 本番png = 本番.書き出し先().目視用の絵へ変換する()?;
    Ok(format!(
        "{画素判定}、シーンパスの発行数は{}、シーン可視数は{}、材質の色の絵は{}、本番経路の絵は{}",
        計数.シーン.発行数,
        計数.シーン.可視数,
        平面png.display(),
        本番png.display()
    ))
}

/// 外部のアセットリポジトリが無い環境では、実行時アセット生成が小物の宣言を飛ばしたうえで成功する。
/// その場合はシーンの読込がカタログ未登録で落ちるため、どのファイルが作られなかったかをここで名指しして落とす。
fn 実行時形式の実在を確かめる() -> Result<(), 小物の材質境界の検収エラー> {
    let パス = 検証の出力ルート::既定().置き場の中のファイル(crate::compile_assets::板の世界の実行時形式の置き場, 実行時形式のファイル名);
    if パス.is_file() {
        return Ok(());
    }
    Err(小物の材質境界の検収エラー::実行時形式が作られていない { パス })
}
