//! 地表の層の検収エラーを人が読む1文へ写すトレイト実装。枝ごとに、どの前提がどう破れたかを出す。
//! 実装を型の定義と分けるのは、外部トレイトの実装が型自身の持ち物とは別の軸であるためである。

use std::fmt;

use super::地表の層の検収エラー;

impl fmt::Display for 地表の層の検収エラー {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::検収の器が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::判定が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::世界のソースを書き出せなかった(理由) => write!(書き手, "検収用の世界のソースを書き出せなかった: {理由}"),
            Self::実行時アセットを焼けなかった => write!(書き手, "検収用の世界の実行時アセットを焼けなかった"),
        }
    }
}
