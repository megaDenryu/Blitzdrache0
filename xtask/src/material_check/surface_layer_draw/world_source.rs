//! 検収用のエディター世界のソースを書き出す型。担当するのは、平らな高さ格子と条件ごとの重みの格子と
//! 版付きのチャンクソースと目録を、1つの置き場の下へ揃って書くことである。
//!
//! 本物の`assets/editor_world/`を書き換えずに専用の世界を作るのは、オーナーが編集した世界の中身が
//! 判定値になると、編集のたびに検収が動いてしまうためである。層のタイル画像と起動時シーンのキツネは
//! 本物の置き場から写す(`copy_from_assets`)。どちらも検収の材料であり、世界の中身ではないからである。
//!
//! チャンクの座標を負から始めるのは、世界の中心をワールドの原点へ置くためである。既定のカメラは原点を注視するため、
//! 座標を0から始めると世界の隅から外を向くことになる。

mod copy_from_assets;
mod write_chunk;

use std::path::{Path, PathBuf};

use blitz_asset_compiler::高さ格子諸元;

use super::error::地表の層の検収エラー;
use super::weight_pattern::塗り分けの形;

/// チャンクの一辺。本物のエディター世界と同じ値にし、焼く経路が同じ大きさの格子を扱う。
const チャンク一辺メートル: f32 = 256.0;

/// 一辺のチャンク数。中心を原点へ置くため座標は-1と0の2つになる。
const 一辺のチャンク数: i32 = 2;

/// 高さ格子の細かさと重なり幅。本物のエディター世界と同じにして、重みの格子の一辺も同じ数にする。
const 辺分割数: u16 = 64;
const 重なり幅: u8 = 1;

/// エディター世界のソースディレクトリ名。焼く側の`対象世界::エディターの世界名()`と同じ綴りでなければ読まれない。
const 世界のディレクトリ名: &str = "editor_world";

pub(super) struct 検収用の世界のソース {
    ソースルート: PathBuf,
}

impl 検収用の世界のソース {
    /// 条件の塗り分けで世界を書き出す。呼ばれるのは条件ごとに1回であり、書き終えた時点で焼ける形になっている。
    pub(super) fn 書き出す(ソースルート: PathBuf, 形: 塗り分けの形) -> Result<Self, 地表の層の検収エラー> {
        let 世界 = Self { ソースルート };
        let 世界のディレクトリ = 世界.ソースルート.join(世界のディレクトリ名);
        世界.作り直す(&世界のディレクトリ)?;
        copy_from_assets::素材を写す(&世界.ソースルート)?;
        let 諸元 = 諸元を作る();
        let mut 目録の行一覧 = Vec::new();
        for 座標z in 座標の並び() {
            for 座標x in 座標の並び() {
                目録の行一覧.push(write_chunk::チャンク1件を書く(&世界のディレクトリ, 諸元, 形, 座標x, 座標z)?);
            }
        }
        世界.目録を書く(&世界のディレクトリ, &目録の行一覧)?;
        Ok(世界)
    }

    pub(super) fn ソースルート(&self) -> &Path {
        &self.ソースルート
    }

    /// 前の条件が書いた重みが残らないよう、書く前に消してから作る。
    fn 作り直す(&self, 世界のディレクトリ: &Path) -> Result<(), 地表の層の検収エラー> {
        if 世界のディレクトリ.exists() {
            std::fs::remove_dir_all(世界のディレクトリ).map_err(書き出しの破れ)?;
        }
        std::fs::create_dir_all(世界のディレクトリ).map_err(書き出しの破れ)
    }

    fn 目録を書く(&self, 世界のディレクトリ: &Path, 行一覧: &[String]) -> Result<(), 地表の層の検収エラー> {
        let mut 本文 = format!("blitz_chunk_directory 2 {チャンク一辺メートル}\n");
        for 行 in 行一覧 {
            本文.push_str(行);
            本文.push('\n');
        }
        std::fs::write(世界のディレクトリ.join("chunk_directory.txt"), 本文).map_err(書き出しの破れ)
    }
}

/// 世界の中心から端までのメートル。塗り分けの形がワールドの位置を割合へ写すのに使う。
pub(super) fn 世界の半径メートル() -> f32 {
    チャンク一辺メートル * f32::from(u8::try_from(一辺のチャンク数).unwrap_or(1)) / 2.0
}

pub(super) fn 座標の並び() -> std::ops::Range<i32> {
    -一辺のチャンク数 / 2..一辺のチャンク数 / 2
}

pub(super) fn 諸元を作る() -> 高さ格子諸元 {
    高さ格子諸元::生成する(辺分割数, 重なり幅, チャンク一辺メートル).unwrap_or_else(|誤り| panic!("検収用の高さ格子の諸元が不正だった: {誤り}"))
}

pub(super) fn 書き出しの破れ(誤り: std::io::Error) -> 地表の層の検収エラー {
    地表の層の検収エラー::世界のソースを書き出せなかった(誤り.to_string())
}
