//! 地表の層の重ね合わせの絵に対する判定。受け取るのは読み戻した絵、返すのは合否である。
//!
//! 判定は3つである。象限の世界で四隅の色が層のタイルの純色と一致すること(4層すべてが1枚に出る)、
//! 北を向いた絵と南を向いた絵で四隅の層が180度入れ替わること(南北と東西の向き)、
//! 台地の世界でカメラが見る範囲がすべて1つの層の純色であること(チャンクの境目で色が飛ばない)である。

use crate::acceptance::{判定の名前, 判定の破れ, 読み戻し画像};

use super::layer_color::{層の色, 純色でない画素数を数える, 隅の位置};

/// 象限の世界を北から見たときの、四隅の層。左上が北西・右上が北東・左下が南西・右下が南東を映す。
const 北から見た四隅の層: [層の色; 4] = [層の色::草, 層の色::泥, 層の色::岩, 層の色::砂];

/// 南から見たときの四隅の層。カメラが180度回るため、北から見た並びがそのまま逆順になる。
const 南から見た四隅の層: [層の色; 4] = [層の色::砂, 層の色::岩, 層の色::泥, 層の色::草];

/// 北が岩で南が砂の世界を北から見たときの、四隅の層。上の2つはカメラより北、下の2つは手前の南である。
/// 重みの行を南北で取り違えると、チャンクの中ほどより向こうの草が回り込んで岩も砂も消える。
const 北が岩で南が砂の四隅の層: [層の色; 4] = [層の色::岩, 層の色::岩, 層の色::砂, 層の色::砂];

/// 台地の世界で、砂の純色でない画素として認める数。起動時シーンのキツネが画面の中央に立つため、
/// その分だけを許す。境目の標本が反対側の端と混ざる実装では、境目に沿った帯が画面の数割を占める。
const 台地の世界で混ざり物と認める画素数: u64 = 8000;

pub(super) fn 北から見た象限の四隅を検査する(画像: &読み戻し画像) -> Result<(), 判定の破れ> {
    四隅の層を検査する(画像, "北を向いた象限", &北から見た四隅の層)
}

pub(super) fn 南から見た象限の四隅を検査する(画像: &読み戻し画像) -> Result<(), 判定の破れ> {
    四隅の層を検査する(画像, "南を向いた象限", &南から見た四隅の層)
}

pub(super) fn 北が岩で南が砂の四隅を検査する(画像: &読み戻し画像) -> Result<(), 判定の破れ> {
    四隅の層を検査する(画像, "北が岩で南が砂", &北が岩で南が砂の四隅の層)
}

/// 台地の内側だけを見る構図であるため、絵はキツネを除いて砂の純色1色になる。
pub(super) fn 台地の世界が一様であることを検査する(画像: &読み戻し画像) -> Result<u64, 判定の破れ> {
    let 混ざり物 = 純色でない画素数を数える(画像, 層の色::砂);
    台地の混ざり物の判定名().上限を課す(混ざり物, 台地の世界で混ざり物と認める画素数)?;
    Ok(混ざり物)
}

fn 四隅の層を検査する(
    画像: &読み戻し画像, 条件の呼び名: &str, 期待する層: &[層の色; 4]
) -> Result<(), 判定の破れ> {
    for (隅, 層) in 隅の位置::四隅.iter().zip(期待する層) {
        let 画素 = 隅.画素を読む(画像);
        四隅の色の判定名(条件の呼び名, *隅, *層).綴りの一致を課す(&format!("{画素:?}"), &色の綴り(*層, 画素))?;
    }
    Ok(())
}

/// 実測が許容の内側なら期待の綴りを実測と同じにし、外れていれば純色の綴りを返す。
/// 綴りの一致で課すのは、成分ごとの差の許容を持ったまま「どの色が出たか」を破れの文面へ載せるためである。
fn 色の綴り(層: 層の色, 画素: [u8; 3]) -> String {
    if 層.画素が一致するか(画素) {
        format!("{画素:?}")
    } else {
        format!("{:?}", 層.純色())
    }
}

fn 四隅の色の判定名(条件の呼び名: &str, 隅: 隅の位置, 層: 層の色) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{条件の呼び名}の絵の{}の色({}のタイルの純色{:?}と成分ごとに近いこと)",
        隅.呼び名(),
        層.呼び名(),
        層.純色()
    ))
}

fn 台地の混ざり物の判定名() -> 判定の名前 {
    判定の名前::定数から生成する("台地の世界で砂の純色でない画素の数")
}
