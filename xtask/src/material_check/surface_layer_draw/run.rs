//! 検収1回ぶんの起動の指定。受け取るのは向きの条件、返すのは実行環境へ渡す起動指定である。
//! 起こす手順そのものは検収の共通語彙の実行環境が持ち、ここは条件ごとに違う向きだけを決める。
//!
//! ライティングを切るのは、層のタイルの純色をそのまま画素で読み取るためである。光の当たり方が混ざると、
//! 色の違いが層の違いによるものか決められない。ポスト処理と空も切る。明るさの圧縮は色を移し、
//! 空は背景の画素を層の色と見分けにくくする。
//!
//! チャンクを本番のストリーミング経路で載せるのは、エディターの世界の地面がチャンクとしてしか存在しないためである。
//! 俯角を既定より深くするのは、地面が画面のほとんどを占める構図にして、層ごとの画素を数えられるようにするためである。

use std::path::PathBuf;

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収エラー, 検収シーン名
};

/// エディターの世界の起動時シーンの綴り。焼く側の`asset_definition_list`が同じ綴りで登録する。
const シーン名: 検収シーン名 = 検収シーン名::生成する("terrain_editor_world");

/// 描くフレーム数。ストリーミングが4チャンクを載せ終えるまでの余裕を取る。
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(120);

/// RAMとVRAMの上限。4チャンクぶんの地形と重みのテクスチャに対して余裕を持つ値であり、この検収は縮退を見ない。
const 上限バイト数: &str = "134217728";

/// 既定の俯角20度へ加える度数。合わせて50度になり、地面が画面の下半分を大きく占める。
const 俯角の追加度数: &str = "30";

/// 先読み半径。中心のチャンクの隣までを載せれば、この2×2の世界は全部が常駐する。
const 先読み半径: &str = "2";

const 値を持たない選択肢: [&str; 4] = ["--unlit", "--no-post", "--no-sky", "--streaming"];

/// カメラが向く方位。既定の姿勢は北を向いており、南を向く条件は方位を180度足す。
#[derive(Clone, Copy)]
pub(super) enum 見る向き {
    北,
    南,
}

impl 見る向き {
    pub(super) const fn 呼び名(self) -> &'static str {
        match self {
            Self::北 => "north",
            Self::南 => "south",
        }
    }

    const fn 方位の追加度数(self) -> &'static str {
        match self {
            Self::北 => "0",
            Self::南 => "180",
        }
    }
}

pub(super) fn 実行環境を作る(
    アセットルート: PathBuf, 出力ディレクトリ: PathBuf
) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::パスから生成する(アセットルート),
        出力ディレクトリ,
    )
}

pub(super) fn 起動指定を組み立てる(向き: 見る向き) -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数)
        .選択肢をまとめて足す(&値を持たない選択肢)
        .値を持つ選択肢を足す("--streaming-preload-radius", 先読み半径)
        .値を持つ選択肢を足す("--streaming-ram-limit", 上限バイト数)
        .値を持つ選択肢を足す("--streaming-vram-limit", 上限バイト数)
        .値を持つ選択肢を足す("--camera-pitch", 俯角の追加度数)
        .値を持つ選択肢を足す("--camera-yaw", 向き.方位の追加度数())
}
