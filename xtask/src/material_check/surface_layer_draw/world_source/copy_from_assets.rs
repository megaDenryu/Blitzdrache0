//! 本物の`assets/`から、検収用のソースルートへ素材を写す工程。受け取るのはソースルートと写す置き場の名前、
//! 返すのは写した成否である。
//!
//! 検収用の世界が素材を描き起こさないのは、判定の期待値が本物のタイルの色だからである。別の絵を用意すると、
//! 絵の色と判定の期待値という2つの正本ができる。キツネを写すのは、エディターの世界の宣言が起動時シーンとして
//! それを必ず読むためであり、絵の判定はキツネを見ない。
//!
//! 写すだけで書き換えないため、本物の`assets/`はこの検収で1バイトも変わらない。

use std::path::Path;

use super::super::error::地表の層の検収エラー;
use super::書き出しの破れ;

/// 層のタイル画像の置き場の名前。焼く側の`地表層タイルの置き場`がソースルートの下のこの名前を読む。
const タイルのディレクトリ名: &str = "surface_layer_textures";

/// 起動時シーンのキツネの置き場。`フォックスのソース`が指すファイルの親ディレクトリである。
const キツネのディレクトリ名: &str = "samples/Fox";

/// 本物のソースルート。リポジトリの`assets/`である。
const 本物のソースルート: &str = "assets";

pub(super) fn 素材を写す(ソースルート: &Path) -> Result<(), 地表の層の検収エラー> {
    for 置き場 in [タイルのディレクトリ名, キツネのディレクトリ名] {
        ディレクトリの中のファイルを写す(ソースルート, 置き場)?;
    }
    Ok(())
}

fn ディレクトリの中のファイルを写す(ソースルート: &Path, 置き場: &str) -> Result<(), 地表の層の検収エラー> {
    let 写し先 = ソースルート.join(置き場);
    std::fs::create_dir_all(&写し先).map_err(書き出しの破れ)?;
    let 写し元 = Path::new(本物のソースルート).join(置き場);
    for 項目 in std::fs::read_dir(&写し元).map_err(書き出しの破れ)? {
        let 項目 = 項目.map_err(書き出しの破れ)?;
        if 項目.path().is_file() {
            std::fs::copy(項目.path(), 写し先.join(項目.file_name())).map_err(書き出しの破れ)?;
        }
    }
    Ok(())
}
