//! チャンク1件ぶんのソースを書く工程。受け取るのは置き場と諸元と塗り分けの形とチャンクの座標、
//! 返すのは目録へ載せる1行である。
//!
//! 高さを平らにするのは、この検収が地表の色だけを見るためである。起伏があると、同じ層の面でも
//! 傾きによって画素の位置が変わり、色の数え上げが起伏の形に左右される。

use std::path::Path;

use blitz_asset_compiler::{地表材質の重み格子, 地表材質の重み格子を格納する, 地表材質の重み格子諸元};
use blitz_asset_compiler::{高さ格子, 高さ格子を格納する, 高さ格子諸元};

use super::super::error::地表の層の検収エラー;
use super::super::weight_pattern::塗り分けの形;
use super::{チャンク一辺メートル, 世界の半径メートル, 書き出しの破れ};

pub(super) fn チャンク1件を書く(
    世界のディレクトリ: &Path,
    諸元: 高さ格子諸元,
    形: 塗り分けの形,
    座標x: i32,
    座標z: i32,
) -> Result<String, 地表の層の検収エラー> {
    let 名前 = format!("editor_terrain_x{座標x}_z{座標z}");
    let 高さ格子のファイル名 = format!("{名前}.heightgrid");
    let 重みのファイル名 = format!("{名前}.surfaceweights");
    let ソースのファイル名 = format!("editor_chunk_x{座標x}_z{座標z}.json");

    let 平らな格子 = 平らな高さ格子を作る(諸元);
    std::fs::write(世界のディレクトリ.join(&高さ格子のファイル名), 高さ格子を格納する(&平らな格子)).map_err(書き出しの破れ)?;
    let 重み格子 = 重み格子を作る(諸元, 形, 座標x, 座標z)?;
    std::fs::write(世界のディレクトリ.join(&重みのファイル名), 地表材質の重み格子を格納する(&重み格子)).map_err(書き出しの破れ)?;
    let 本文 = チャンクソースのjson(&高さ格子のファイル名, &重みのファイル名);
    std::fs::write(世界のディレクトリ.join(&ソースのファイル名), 本文).map_err(書き出しの破れ)?;
    Ok(format!("{座標x} {座標z} {名前} {ソースのファイル名}"))
}

fn 平らな高さ格子を作る(諸元: 高さ格子諸元) -> 高さ格子 {
    let 標本数 = usize::try_from(諸元.標本数()).unwrap_or_else(|_| panic!("高さ格子の標本数がusizeに収まらない"));
    高さ格子::生成する(諸元, vec![0.0; 標本数]).unwrap_or_else(|誤り| panic!("平らな高さ格子を作れなかった: {誤り}"))
}

/// 標本の添字をワールドのメートルへ写してから塗り分けの形へ問う。写しをここへ置くことで、
/// 塗り分けの形はチャンクの座標も格子の細かさも知らずに済む。
fn 重み格子を作る(
    高さ格子の諸元: 高さ格子諸元,
    形: 塗り分けの形,
    座標x: i32,
    座標z: i32,
) -> Result<地表材質の重み格子, 地表の層の検収エラー> {
    let 一辺 = 高さ格子の諸元.格子点数();
    let 諸元 = 地表材質の重み格子諸元::生成する(一辺)?;
    let 刻み = 高さ格子の諸元.刻みメートル();
    let 原点東 = チャンク一辺メートル * 実数へ写す(座標x);
    let 原点南 = チャンク一辺メートル * 実数へ写す(座標z);
    let 半径 = 世界の半径メートル();
    let mut 重み一覧 = Vec::new();
    for 標本添字z in 0..一辺 {
        for 標本添字x in 0..一辺 {
            let 東 = 原点東 + 刻み * 実数へ写す(標本添字x);
            let 南 = 原点南 + 刻み * 実数へ写す(標本添字z);
            重み一覧.extend_from_slice(&形.標本の重み(東, 南, 半径));
        }
    }
    Ok(地表材質の重み格子::生成する(諸元, 重み一覧)?)
}

/// 値を落とさずf32へ写せるのはi16の範囲だけである。チャンクの座標も標本の添字もこの範囲に収まる。
fn 実数へ写す<数: TryInto<i16>>(値: 数) -> f32 {
    let 狭めた: i16 = 値.try_into().unwrap_or_else(|_| panic!("検収用の世界の添字がi16へ収まらない"));
    f32::from(狭めた)
}

fn チャンクソースのjson(高さ格子のファイル名: &str, 重みのファイル名: &str) -> String {
    format!(
        "{{\n  \"形式版\": 2,\n  \"高さ格子\": \"{高さ格子のファイル名}\",\n  \"地表材質の重み格子\": \"{重みのファイル名}\",\n  \"建物配置一覧\": []\n}}\n"
    )
}
