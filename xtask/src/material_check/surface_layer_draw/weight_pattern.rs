//! 検収用の世界が塗る地表材質の重みの形。受け取るのは標本のワールド位置、返すのは4層の重みである。
//!
//! 重みをワールド位置の関数として決めるのは、チャンクの境界をまたいで同じ塗り分けが続くことを、
//! 書き出す側の作りとして保証するためである。チャンクごとに別の規則で塗ると、境界で色が飛ぶのが
//! 塗り分けの都合なのか標本の位置ずれなのかを判定が区別できない。

use blitz_asset_compiler::地表層の数;

/// 検収の条件。条件ごとに塗り分けの形が変わり、それぞれ別の判定が読む。
#[derive(Clone, Copy)]
pub(super) enum 塗り分けの形 {
    /// 4つの象限を層0から層3で塗り分ける。北西が層0、北東が層1、南西が層2、南東が層3である。
    /// 層と象限を1対1にすることで、1枚の絵から「どの層のタイルが出ているか」と「南北と東西の向き」を同時に読める。
    象限ごとの単一の層,
    /// 世界の中央の正方形のうち、北半分を層2(岩)で、南半分を層3(砂)で塗り、外側を層0(草)で塗る。
    /// 岩と砂の境目はチャンクの境目に、岩と草の境目はチャンクの中ほどにある。重みの行を南北で取り違えると、
    /// チャンクの中ほどより向こうの草が手前へ回り込み、カメラが見る範囲から岩と砂が消える。
    北が岩で南が砂,
    /// 世界の中央の正方形の台地だけを層3(砂)で塗り、その外側を層0(草)で塗る。台地の縁は1つのチャンクの内側にあり、
    /// チャンクの向かい合う端が別の層になる。境界の標本が反対側の端と混ざる実装では、チャンクの境目に草の帯が出る。
    /// 台地の内側は境目をまたいで一様な砂であり、カメラが見る範囲はすべてその内側に入る。
    中央の台地だけ砂,
}

impl 塗り分けの形 {
    pub(super) const fn 呼び名(self) -> &'static str {
        match self {
            Self::象限ごとの単一の層 => "quadrant",
            Self::北が岩で南が砂 => "north_south",
            Self::中央の台地だけ砂 => "plateau",
        }
    }

    /// 標本1つぶんの重み。ワールドのXとZは、この世界の中心を原点として測ったメートルである。
    pub(super) fn 標本の重み(self, 東メートル: f32, 南メートル: f32, 世界の半径メートル: f32) -> [u8; 地表層の数] {
        match self {
            Self::象限ごとの単一の層 => 象限の重み(東メートル, 南メートル),
            Self::北が岩で南が砂 => 南北で分けた重み(東メートル, 南メートル, 世界の半径メートル),
            Self::中央の台地だけ砂 => 台地の重み(東メートル, 南メートル, 世界の半径メートル),
        }
    }
}

/// 満量の重み。合計が255になるため、画素にはその層のタイルの色がそのまま出る。
fn 単一の層の重み(層番号: usize) -> [u8; 地表層の数] {
    let mut 重み = [0_u8; 地表層の数];
    重み[層番号] = 255;
    重み
}

fn 象限の重み(東メートル: f32, 南メートル: f32) -> [u8; 地表層の数] {
    let 北側 = 南メートル < 0.0;
    let 西側 = 東メートル < 0.0;
    match (北側, 西側) {
        (true, true) => 単一の層の重み(0),
        (true, false) => 単一の層の重み(1),
        (false, true) => 単一の層の重み(2),
        (false, false) => 単一の層の重み(3),
    }
}

/// 台地の縁までのメートル。世界の半径の半分に取ると、縁がちょうどチャンクの中ほどへ来る。
/// 縁をチャンクの中ほどへ置くのは、重みの行を南北で取り違えたときに、縁の向こう側とこちら側が入れ替わって
/// カメラが見る範囲の色が変わるようにするためである。縁がチャンクの端に近いと、取り違えても絵がほとんど変わらない。
fn 台地の縁までのメートル(世界の半径メートル: f32) -> f32 {
    世界の半径メートル / 2.0
}

fn 台地の内側か(東メートル: f32, 南メートル: f32, 世界の半径メートル: f32) -> bool {
    let 縁 = 台地の縁までのメートル(世界の半径メートル);
    東メートル.abs() <= 縁 && 南メートル.abs() <= 縁
}

fn 南北で分けた重み(東メートル: f32, 南メートル: f32, 世界の半径メートル: f32) -> [u8; 地表層の数] {
    if !台地の内側か(東メートル, 南メートル, 世界の半径メートル) {
        return 単一の層の重み(0);
    }
    if 南メートル <= 0.0 {
        単一の層の重み(2)
    } else {
        単一の層の重み(3)
    }
}

fn 台地の重み(東メートル: f32, 南メートル: f32, 世界の半径メートル: f32) -> [u8; 地表層の数] {
    if 台地の内側か(東メートル, 南メートル, 世界の半径メートル) {
        単一の層の重み(3)
    } else {
        単一の層の重み(0)
    }
}
