//! 上位の色それぞれが物体画素に占める割合と、色どうしが別の材質と言えるかの判定。
//! 受け取るのは物体画素の総数と多い順に並べた色、返すのは合否である。物体そのものの占有率は親の`judgment`が見る。

use crate::acceptance::{判定の名前, 検収エラー, 画素の占める割合};

/// 材質1つが物体画素のうち占める割合の下限。最も小さい材質でも、輪郭のにじみとは桁が違う面積を持つ。
const 材質1つの占有率の下限: f64 = 0.06;
/// 上位の色が物体画素を覆う割合の下限。残りは面と面の境界にできるにじみである。
const 覆う割合の下限: f64 = 0.80;
/// 2つの色を別の材質と言うための、対応する成分の差の下限。読み戻しの符号化の揺れ(数階調)とは桁が違う値である。
const 成分差の下限: u8 = 30;

const 上位の色が覆う割合: 判定の名前 =
    判定の名前::定数から生成する("上位の色が物体画素を覆う割合(下回るなら塗りが材質ごとに一様でない)");

pub(super) fn 割合を検査する(物体画素数: usize, 上位: &[([u8; 3], usize)]) -> Result<(), 検収エラー> {
    let mut 合計 = 0usize;
    for (色, 件数) in 上位 {
        let 割合 = 画素の占める割合::部分と全体から求める(*件数, 物体画素数)?;
        材質1つが占める割合の判定名(*色).下限を課す(割合.値(), 材質1つの占有率の下限)?;
        合計 += 件数;
    }
    let 覆う割合 = 画素の占める割合::部分と全体から求める(合計, 物体画素数)?;
    上位の色が覆う割合.下限を課す(覆う割合.値(), 覆う割合の下限)?;
    Ok(())
}

pub(super) fn 互いに別の色であることを検査する(上位: &[([u8; 3], usize)]) -> Result<(), 検収エラー> {
    for (添字, (色, _)) in 上位.iter().enumerate() {
        for (相手, _) in &上位[添字 + 1..] {
            let 最大の差 = (0..3).map(|成分| 色[成分].abs_diff(相手[成分])).max().unwrap_or(0);
            成分の差の判定名(*色, *相手).下限を課す(最大の差, 成分差の下限)?;
        }
    }
    Ok(())
}

fn 材質1つが占める割合の判定名(色: [u8; 3]) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("色{色:?}が物体画素に占める割合(下回るなら材質が縮退している)"))
}

fn 成分の差の判定名(色: [u8; 3], 相手: [u8; 3]) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("色{色:?}と色{相手:?}の対応する成分の差の最大(下回るなら別の材質と言えない)"))
}
