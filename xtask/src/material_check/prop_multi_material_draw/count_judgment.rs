//! 計器から見た材質の本数の判定。受け取るのは1回の実行の計数報告、返すのは合否である。
//!
//! 画素の判定と分けるのは、入力も根拠も別だからである。画素は「作者が与えた色が絵に出たか」を見るのに対し、
//! ここは「材質スロットの数だけ描画発行が立ったか」という描画側の数を見る。
//! glbは材質スロットごとにプリミティブを分け、レンダラーはプリミティブごとに1回発行するため、
//! 材質が縮退すれば発行数が減る。画素が偶然通っても、この数がプリミティブの脱落を捕まえる。

use crate::acceptance::{判定の名前, 判定の破れ};
use crate::report_parse::計数報告;

const 検証層の指摘: 判定の名前 = 判定の名前::定数から生成する("実行で出た検証層の指摘");

pub(super) fn 検査する(計数: &計数報告, 材質の数: usize) -> Result<(), 判定の破れ> {
    crate::count_consistency::計数の整合を検査する("prop-multi-material-draw", 計数)?;
    // 材質の数はこの入口が持つ小さな定数であるため、写しが収まらない側へ倒れることはない。
    let 期待発行数 = u64::try_from(材質の数).unwrap_or(u64::MAX);
    シーンパスの発行数の判定名(材質の数).一致を課す(計数.シーン.発行数, 期待発行数)?;
    検証層の指摘.零件であることを課す(計数.validation件数)
}

fn シーンパスの発行数の判定名(材質の数: usize) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("シーンパスの発行数(材質{材質の数}個ぶんのプリミティブが立てばその数になる)"))
}
