//! 材質の境界が実アセットの絵に出ていることの判定。受け取るのは色の分布、返すのは合格の要約である。
//! 計器から見た判定は`count_judgment`が持つ。
//!
//! 判定の骨は「上位の色が材質の数だけ立ち、そのどれもが小さすぎず、互いに別の色であり、合わせて物体をほぼ覆う」である。
//! 材質の縮退はこの形で必ず落ちる。全プリミティブが1つの材質へ縮退すれば色の山は1本になり、
//! 2位と3位には輪郭のにじみしか残らないため、下限の割合を満たせない。
//! 色を絶対値で照合しないのは、アセットが宣言したベースカラーの写しを検収側へ持たないためである。
//! 写しを持つと、アセットの色を変えたときにこの検収だけが無言で通らなくなる。
//!
//! 上位の色それぞれが物体画素に占める割合と、色どうしが別の材質と言えるかは`color_share`が見る。

mod color_share;

use super::material_pixels::色の分布;
use crate::acceptance::{判定の名前, 検収エラー, 画素の占める割合};

/// 物体が占める画素の割合の下限。これを下回るなら小物が描かれていないか、構図から外れている。
const 物体の占有率の下限: f64 = 0.02;

const 立った色の種類: 判定の名前 = 判定の名前::定数から生成する("背景でない画素に立った色の種類(材質の数ぶんの色が立つはずである)");
const 物体が占める割合: 判定の名前 =
    判定の名前::定数から生成する("物体が占める割合(下回るなら小物が構図から外れているか極端に小さく写っている)");

pub(super) fn 材質の境界を検査する(分布: &色の分布) -> Result<String, 検収エラー> {
    let 上位 = &分布.多い順の色;
    立った色の種類.下限を課す(上位.len(), super::材質の数)?;
    let 上位 = &上位[..super::材質の数];
    占有率を検査する(分布)?;
    color_share::割合を検査する(分布.物体画素数, 上位)?;
    color_share::互いに別の色であることを検査する(上位)?;
    Ok(format!(
        "背景色{:?}、物体画素{}、上位{}色は{:?}",
        分布.背景色,
        分布.物体画素数,
        super::材質の数,
        上位
    ))
}

fn 占有率を検査する(分布: &色の分布) -> Result<(), 検収エラー> {
    if 分布.物体画素数 == 0 {
        return Err(背景色でない画素の判定名(分布.背景色).あるはずのものが無い破れ().into());
    }
    let 占有率 = 画素の占める割合::部分と全体から求める(分布.物体画素数, 分布.全画素数)?;
    物体が占める割合.下限を課す(占有率.値(), 物体の占有率の下限)?;
    Ok(())
}

fn 背景色でない画素の判定名(背景色: [u8; 3]) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("背景色{背景色:?}でない画素"))
}
