//! 記録側の切替の判定。触れるのは2つの計数報告の記録側の3つの数だけであり、画素にも束縛回数にも触れない。
//!
//! シーンのパイプライン切替が材質の数で増えないことと、材質切替が描いた材質の数と一致することをここで固定する。
//! 材質を2件に分けてもパイプラインが1本のままであることが「材質IDをパイプラインキーへ混ぜていない」ことの実行の値による証拠であり、
//! 材質切替が材質の数と一致することが、整列で同じ材質の発行が連続していることの証拠である
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段6の検収ゲート(v))。

use crate::acceptance::{判定の名前, 判定の破れ};
use crate::report_parse::計数報告;

/// 布を持たないこの検収入口では、シーンパスで束縛するパイプラインは材質描画族の1本だけである。
const シーンのパイプライン切替: u64 = 1;

pub(super) fn 記録側の切替を検査する(二材質: &計数報告, 単一材質: &計数報告) -> Result<(), 判定の破れ> {
    for (名前, 計数, 材質の数) in [("2材質", 二材質, 2), ("1材質", 単一材質, 1)] {
        パイプライン切替の判定名(名前).一致を課す(計数.シーン.パイプライン切替, シーンのパイプライン切替)?;
        材質切替の判定名(名前, 材質の数).一致を課す(計数.シーン.材質切替, 材質の数)?;
        描画数が発行数と一致することを確かめる(名前, 計数)?;
        シャドウが材質切替を数えないことを確かめる(名前, 計数)?;
    }
    Ok(())
}

/// 発行数は作業領域が積んだ件数、描画数は記録が`vkCmdDrawIndexed`を呼んだ回数である。観測地点が違う2つが一致することが、
/// 記録の経路が発行を落としても二重に積んでもいないことの証拠になる。布を持たないこの入口ではシーンパスの描画が全部この発行から出る。
fn 描画数が発行数と一致することを確かめる(条件名: &str, 計数: &計数報告) -> Result<(), 判定の破れ> {
    for (パス名, パス) in crate::report_parse::全パスを並べる(計数) {
        描画数の判定名(条件名, &パス名).一致を課す(パス.描画数, パス.発行数)?;
    }
    Ok(())
}

/// シャドウ記録は材質のセットも材質レコードも読まないため、材質切替を1回も数えない。
fn シャドウが材質切替を数えないことを確かめる(条件名: &str, 計数: &計数報告) -> Result<(), 判定の破れ> {
    for (番号, パス) in 計数.距離区分別のシャドウ.iter().enumerate() {
        シャドウの材質切替の判定名(条件名, 番号).零件であることを課す(パス.材質切替)?;
    }
    Ok(())
}

fn パイプライン切替の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}のシーンパスのパイプライン切替の回数(材質の数で増えないはずである)"))
}

fn 材質切替の判定名(条件名: &str, 材質の数: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{条件名}のシーンパスの材質切替の回数(整列で同じ材質の発行が連続していれば描いた材質{材質の数}件と一致する)"
    ))
}

fn 描画数の判定名(条件名: &str, パス名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}の{パス名}の描画数(発行数と一致するはずである)"))
}

fn シャドウの材質切替の判定名(条件名: &str, 番号: usize) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}のシャドウ距離区分{番号}が数えた材質切替"))
}
