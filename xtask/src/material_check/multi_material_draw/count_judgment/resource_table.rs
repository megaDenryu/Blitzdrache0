//! 資源表世代とディスクリプタセットの束縛回数についての判定。担当するのは、材質を1件から2件へ増やしても
//! 常駐画像が正準フォールバックの枚数に収まることと、材質のセットの束縛がパスごと1回のままであることを見ることである。
//! 発行数と可視数の突き合わせは親の`count_judgment`が持つ。

use crate::acceptance::{判定の名前, 判定の破れ};
use crate::report_parse::計数報告;

/// テクスチャを1枚も持たない材質だけのシーンで常駐する画像の枚数。世代で共有する正準フォールバックだけである。
/// 白・平坦法線・中立金属粗さに、地表の層の重ね合わせが読む先頭の層だけの重みを足した4枚である
/// (正本は`crates/blitz_render/src/vulkan/material_table/fallback_usage.rs`の`正準フォールバック用途::全用途`)。
const 正準フォールバックの枚数: u64 = 4;
const 材質のセット番号: usize = 2;
const ジオメトリのセット番号: usize = 1;

/// 材質が1件から2件へ増えても枚数が変わらないことが、無しの材質が材質ごとの既定の画素を持たないことの実配線の証拠になる
/// (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段4bの検収ゲート(ii))。
pub(super) fn 正準フォールバックが材質で複製されないことを確かめる(
    二材質: &計数報告,
    単一材質: &計数報告,
) -> Result<(), 判定の破れ> {
    for (名前, 計数, 期待する材質件数) in [("2材質", 二材質, 2), ("1材質", 単一材質, 1)] {
        資源表世代の材質件数の判定名(名前).一致を課す(計数.材質件数, 期待する材質件数)?;
        常駐画像枚数の判定名(名前).一致を課す(計数.常駐画像枚数, 正準フォールバックの枚数)?;
    }
    Ok(())
}

/// 材質のセット(番号2)はパスごと1回であり、材質もプリミティブも増えた2材質の側でも回数が変わらない。
/// ジオメトリのセット(番号1)は発行ごとに結ぶため、こちらは増えることを同時に確かめて、計器が動いていることも見る
/// (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段4bの検収ゲート(iii))。
pub(super) fn 材質のセットの束縛が増えないことを確かめる(
    二材質: &計数報告, 単一材質: &計数報告
) -> Result<(), 判定の破れ> {
    for (名前, 計数) in [("2材質", 二材質), ("1材質", 単一材質)] {
        let Some(回数) = 計数.セット別束縛回数.get(材質のセット番号).copied() else {
            return Err(報告のセット別束縛回数の判定名(名前).あるはずのものが無い破れ());
        };
        材質のセットの束縛回数の判定名(名前).一致を課す(回数, 1)?;
    }
    let 二材質のジオメトリ = 二材質.セット別束縛回数.get(ジオメトリのセット番号).copied().unwrap_or(0);
    let 単一材質のジオメトリ = 単一材質.セット別束縛回数.get(ジオメトリのセット番号).copied().unwrap_or(0);
    ジオメトリのセットの束縛が増えることの判定名(二材質のジオメトリ, 単一材質のジオメトリ)
        .真であることを課す(二材質のジオメトリ > 単一材質のジオメトリ)
}

fn 資源表世代の材質件数の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}の資源表世代の材質件数"))
}

fn 常駐画像枚数の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{条件名}の常駐画像枚数(正準フォールバックの{正準フォールバックの枚数}枚に収まるはずである)"
    ))
}

fn 報告のセット別束縛回数の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}の報告のセット番号{材質のセット番号}の束縛回数"))
}

fn 材質のセットの束縛回数の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}の材質のセットの束縛回数(パスごと1回のはずである)"))
}

/// 実測を綴りへ入れるのは、真偽で課す判定が比べた数を文面へ出せないためである。
fn ジオメトリのセットの束縛が増えることの判定名(
    二材質のジオメトリ: u64, 単一材質のジオメトリ: u64
) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "ジオメトリのセットの束縛が2材質{二材質のジオメトリ}回で1材質{単一材質のジオメトリ}回を上回ること(上回らないなら計器が動いていない)"
    ))
}
