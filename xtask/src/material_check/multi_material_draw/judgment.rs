//! 2材質のシーンと1材質の対照に対する画素の判定。受け取るのは2回の実行の代表色、返すのは合否である。
//!
//! 判定は2つである。2材質のシーンで左右の板が別の色に塗られることと、1材質の対照で左右の色が一致することである。
//! 後者が要るのは、左右の色が違うのが材質の違いによるものであり、位置や光の当たり方によるものでないことの根拠だからである。
//! 計数の突き合わせは`count_judgment`が持つ。

use crate::acceptance::{判定の名前, 判定の破れ};
use crate::plate_region::左右の代表色;

/// 左右の代表色が別の材質だと言えるための、対応する成分の差の下限。ベースカラー係数の差はこれよりはるかに大きいため、
/// この下限は「わずかな陰影の違い」と「別の材質」を分ける値として置く。
const 成分差の下限: u64 = 40;

const 単一材質の対照の左の板の色: 判定の名前 = 判定の名前::定数から生成する("1材質の対照の左の板の色(右の板の色と一致するはずである)");

pub(super) fn 二材質の画素を検査する(色: &左右の代表色) -> Result<(), 判定の破れ> {
    左の板が赤の材質であることの判定名(色.右.赤).下限を課す(色.左.赤, 色.右.赤 + 成分差の下限)?;
    右の板が青の材質であることの判定名(色.左.青).下限を課す(色.右.青, 色.左.青 + 成分差の下限)
}

pub(super) fn 単一材質の画素を検査する(色: &左右の代表色) -> Result<(), 判定の破れ> {
    単一材質の対照の左の板の色.綴りの一致を課す(&format!("{:?}", 色.左), &format!("{:?}", 色.右))
}

fn 左の板が赤の材質であることの判定名(右の板の赤: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "左の板の赤(赤の材質なら右の板の赤{右の板の赤}に成分差の下限{成分差の下限}を足した値以上になる)"
    ))
}

fn 右の板が青の材質であることの判定名(左の板の青: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "右の板の青(青の材質なら左の板の青{左の板の青}に成分差の下限{成分差の下限}を足した値以上になる)"
    ))
}
