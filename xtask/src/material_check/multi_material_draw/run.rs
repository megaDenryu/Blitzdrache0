//! 検収1条件ぶんの起動の指定。受け取るのは条件、返すのは実行環境へ渡す起動指定である。
//! 起こす手順そのものは検収の共通語彙の実行環境が持ち、ここは条件ごとに違うシーンだけを決める。
//!
//! 材質境界の検収シーンは板の世界の宣言に並ぶため、実行時アセットルートは`compile-assets`の既定と同じ場所を渡す。
//! シーン名を`multi_material`で始めることが、書き換えもピクセル判定も持たない読み戻しだけの検収計画を選ばせる。
//! 監視対象シェーダーは指定しない。指定しないと埋め込みシェーダーで走り、リポジトリの`shaders/`へ監視の入口が向かない。
//! ライティングを切るのは、材質の違いを画素の色でそのまま読み取るためである。光の当たり方が混ざると、色の違いが材質の違いによるものか決められない。
//! ポスト処理を切るのは、光のにじみが板の外へ回り込んで境界の判定領域を汚さないようにするためである。

use std::path::PathBuf;

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収の実行名, 検収エラー, 検収シーン名,
};

const アセットルート: &str = "target/runtime_assets";
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(12);
const 共通の選択肢: [&str; 4] = ["--unlit", "--no-post", "--report-draw-issue", "--report-memory"];

/// 2条件のシーンの綴り。書き出しの基準名にも同じ綴りを使い、絵のファイル名からどちらの条件かが読めるようにする。
const 二材質のシーンの綴り: &str = "multi_material_two";
const 単一材質のシーンの綴り: &str = "multi_material_one";

pub(super) const 二材質の実行名: 検収の実行名 = 検収の実行名::定数から生成する(二材質のシーンの綴り);
pub(super) const 単一材質の実行名: 検収の実行名 = 検収の実行名::定数から生成する(単一材質のシーンの綴り);

#[derive(Clone, Copy)]
pub(super) enum 条件 {
    二材質,   // 同じ形を2材質2プリミティブで塗る。材質の境界が画素に出ることをこの条件から見る
    単一材質, // 同じ形を1材質1プリミティブで塗る対照。左右の色の一致が材質による違いである根拠になる
}

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::綴りから生成する(アセットルート),
        出力ディレクトリ,
    )
}

pub(super) fn 起動指定を組み立てる(条件: 条件) -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(シーン名(条件), フレーム数).選択肢をまとめて足す(&共通の選択肢)
}

fn シーン名(条件: 条件) -> 検収シーン名 {
    match 条件 {
        条件::二材質 => 検収シーン名::生成する(二材質のシーンの綴り),
        条件::単一材質 => 検収シーン名::生成する(単一材質のシーンの綴り),
    }
}
