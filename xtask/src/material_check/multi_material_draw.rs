//! マルチマテリアル段Cの検収入口。同じ形を2材質2プリミティブで塗るシーンと、1材質1プリミティブで塗る対照を実機で描き、
//! 材質の境界が画素に出ること・シーンパスの発行がプリミティブの数ぶん増えること・可視ID数とシーン可視数が対照と変わらないことを確かめる。
//! 1条件ぶんの起動と読み戻しは`run`、画素の合否は`judgment`、計数の突き合わせは`count_judgment`にある。板の判定領域と代表色は`crate::plate_region`にある。
//! 参照: `_doc/設計/マルチマテリアルと材質境界.md`「段階導入」C段

mod count_judgment;
mod error;
mod judgment;
mod run;
mod switch_judgment;

use std::path::PathBuf;
use std::process::ExitCode;

use error::板の材質境界の検収エラー;

const 出力ディレクトリ: &str = "target/multi_material_draw";

pub fn 多材質シーンの描画を確認する() -> ExitCode {
    match 検収する() {
        Ok(要約) => {
            println!("[xtask] multi-material-draw成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] multi-material-draw失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

fn 検収する() -> Result<String, 板の材質境界の検収エラー> {
    if !crate::gen_source_assets::検証用ソースアセットを生成して成否を返す() || !crate::compile_assets::既定を生成する() {
        return Err(板の材質境界の検収エラー::検証用アセットを生成できなかった);
    }
    let 実行環境 = run::実行環境を作る(PathBuf::from(出力ディレクトリ))?;

    let 二材質 = 実行環境.描いて読み戻す(run::二材質の実行名, &run::起動指定を組み立てる(run::条件::二材質))?;
    二材質.報告().画面へ流す();
    let 単一材質 = 実行環境.描いて読み戻す(run::単一材質の実行名, &run::起動指定を組み立てる(run::条件::単一材質))?;
    単一材質.報告().画面へ流す();
    let 二材質の色 = crate::plate_region::左右の代表色を採る(二材質.画像())?;
    let 単一材質の色 = crate::plate_region::左右の代表色を採る(単一材質.画像())?;
    judgment::二材質の画素を検査する(&二材質の色)?;
    judgment::単一材質の画素を検査する(&単一材質の色)?;
    let 二材質計数 = crate::report_parse::取り出す(二材質.報告())?;
    let 単一材質計数 = crate::report_parse::取り出す(単一材質.報告())?;
    count_judgment::計数を検査する(&二材質計数, &単一材質計数)?;
    switch_judgment::記録側の切替を検査する(&二材質計数, &単一材質計数)?;
    Ok(format!(
        "2材質の代表色は左{:?}・右{:?}、1材質の対照は左右とも{:?}、シーンパス発行数は2材質{}回と1材質{}回、シーン可視数はどちらも{}、可視個体の選別のシーン可視数はどちらも{}、セット別束縛回数は2材質{:?}と1材質{:?}、資源表世代の材質件数は2材質{}と1材質{}で常駐画像はどちらも{}枚",
        二材質の色.左,
        二材質の色.右,
        単一材質の色.左,
        二材質計数.シーン.発行数,
        単一材質計数.シーン.発行数,
        二材質計数.シーン.可視数,
        二材質計数.可視個体の選別.シーン可視数,
        二材質計数.セット別束縛回数,
        単一材質計数.セット別束縛回数,
        二材質計数.材質件数,
        単一材質計数.材質件数,
        二材質計数.常駐画像枚数
    ) + &format!(
        "、シーンパスのパイプライン切替はどちらも{}回、材質切替は2材質{}回と1材質{}回",
        二材質計数.シーン.パイプライン切替, 二材質計数.シーン.材質切替, 単一材質計数.シーン.材質切替
    ))
}
