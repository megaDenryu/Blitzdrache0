//! 有限全数の検証器とは、遷移モデルの状態と遷移を全部列挙して振る舞いの命題を解く検証器のことである。
//!
//! **全部列挙できたときだけ証明済みとする。** 列挙の上限を超えたときは未決定で答え、探索の一部で反例が出なかったことを証明と呼ばない。
//! 構造の原子命題(設計関係が在る・マーカーを持つ・設計関係へ1つも参加していない)はこの検証器の対象ではないため、
//! 偽ではなく「この検証器が扱わない式を含む」で答える。偽で答えると、扱えない問いが成立しない問いと同じ結末になる。
//! 論理の結合の規則はこの木に書かず、`design_proposition` の結合を解く工程へ委譲する(規則を2箇所へ書き写さないため)。
//! 参照: `_doc/設計/設計オントロジー.md` 第9節。

mod solver;

use super::transition_model::{遷移, 遷移モデル};
use crate::design_model::設計概念の識別子;
use crate::design_proposition::{反例, 束縛の割り当て, 検証の方式, 検証結果, 証拠, 項};

/// 列挙してよい対象の件数の上限。1件ごとに命題の本体を解き直すため、これを超えると1回の検証が人が待てる時間を超える。
/// 上限で切ったときは未決定で答えるため、超えたことが黙って通り過ぎることは無い。
const 列挙してよい対象の上限: usize = 100_000;

/// 遷移モデルを保持し、振る舞いの原子命題と到達可能な対象集合を解く検証器。
pub struct 有限全数の検証器 {
    遷移モデル: 遷移モデル,
}

impl 有限全数の検証器 {
    /// 検証の対象になる遷移モデルを受け取って組む。
    pub fn 生成する(遷移モデル: 遷移モデル) -> Self {
        Self { 遷移モデル }
    }

    /// 保持している遷移モデル。
    pub fn 遷移モデル(&self) -> &遷移モデル {
        &self.遷移モデル
    }

    /// いま割り当てられている遷移。`遷移する`の原子は、存在の問いではなくこの遷移についての問いとして解く。
    /// 束縛の割り当てが当てた概念そのものを取り出す口を持たないため、再現の材料の表記で引き当てる。
    fn 割り当てられた遷移(&self, 割り当て: &束縛の割り当て) -> Option<&遷移> {
        割り当て
            .再現の材料へ写す()
            .into_iter()
            .find_map(|(_, 概念の表記)| self.遷移モデル.遷移一覧().iter().find(|候補| 候補.識別子().設計概念の識別子として表す().表記() == 概念の表記))
    }

    /// その遷移がその出来事を生成したか。
    fn 発生するかを解く(&self, 対象の遷移: &遷移, 出来事: &設計概念の識別子) -> 検証結果 {
        if 対象の遷移.その出来事を生成したか(出来事) {
            return 検証結果::証明済み(証拠 {
                方式: 検証の方式::有限全数,
                見た対象の件数: 対象の遷移.生成した出来事一覧().len(),
                説明: format!("遷移 {} が生成した出来事に {} が在る", 対象の遷移.識別子().表記(), 出来事.表記()),
            });
        }
        検証結果::反証済み(反例 {
            方式: 検証の方式::有限全数,
            説明: format!("遷移 {} は {} を生成していない", 対象の遷移.識別子().表記(), 出来事.表記()),
            再現の材料: vec![
                ("前状態".to_string(), 対象の遷移.前状態().表記()),
                ("入力".to_string(), 対象の遷移.入力().表記()),
                ("適用した規則".to_string(), 対象の遷移.適用した規則().表記()),
                ("得られた出来事".to_string(), 得られた出来事の表記(対象の遷移)),
                ("期待した出来事".to_string(), 出来事.表記()),
            ],
        })
    }

    /// その遷移が、その前状態からその入力でその後状態へ移るか。
    fn 遷移するかを解く(&self, 対象の遷移: &遷移, 前状態: &設計概念の識別子, 入力: &設計概念の識別子, 後状態: &設計概念の識別子) -> 検証結果 {
        let 一致するか = 対象の遷移.前状態() == 前状態 && 対象の遷移.入力() == 入力 && 対象の遷移.後状態() == 後状態;
        if 一致するか {
            return 検証結果::証明済み(証拠 {
                方式: 検証の方式::有限全数,
                見た対象の件数: 1,
                説明: format!("遷移 {} は前状態と入力と後状態の3つが一致する", 対象の遷移.識別子().表記()),
            });
        }
        検証結果::反証済み(反例 {
            方式: 検証の方式::有限全数,
            説明: format!("遷移 {} は前状態と入力と後状態の3つが一致しない", 対象の遷移.識別子().表記()),
            再現の材料: vec![
                ("前状態".to_string(), 対象の遷移.前状態().表記()),
                ("入力".to_string(), 対象の遷移.入力().表記()),
                ("後状態".to_string(), 対象の遷移.後状態().表記()),
                ("問うた前状態".to_string(), 前状態.表記()),
                ("問うた入力".to_string(), 入力.表記()),
                ("問うた後状態".to_string(), 後状態.表記()),
            ],
        })
    }

    /// その状態へ初期状態から到達できるか。
    fn 到達可能であるかを解く(&self, 状態: &設計概念の識別子) -> 検証結果 {
        let 到達可能な状態一覧 = self.遷移モデル.到達可能な状態一覧を組む();
        if 到達可能な状態一覧.含むか(状態) {
            return 検証結果::証明済み(証拠 {
                方式: 検証の方式::有限全数,
                見た対象の件数: 到達可能な状態一覧.件数(),
                説明: format!("到達可能な状態を{}件全部列挙し、{} が在った", 到達可能な状態一覧.件数(), 状態.表記()),
            });
        }
        検証結果::反証済み(反例 {
            方式: 検証の方式::有限全数,
            説明: format!("{} へ初期状態から到達できない", 状態.表記()),
            再現の材料: vec![("到達できない状態".to_string(), 状態.表記()), ("到達可能な状態の件数".to_string(), 到達可能な状態一覧.件数().to_string())],
        })
    }
}

/// 反例へ書く、その遷移が実際に生成した出来事の並び。1件も無いときも空文字にせず、そう分かる語を書く。
fn 得られた出来事の表記(対象の遷移: &遷移) -> String {
    if 対象の遷移.生成した出来事一覧().is_empty() {
        return "1件も生成していない".to_string();
    }
    対象の遷移.生成した出来事一覧().iter().map(設計概念の識別子::表記).collect::<Vec<String>>().join(", ")
}
