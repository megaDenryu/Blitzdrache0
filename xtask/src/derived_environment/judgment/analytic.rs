//! 解析的に答えが決まる項目の判定。受け取るのは報告、返すのは最大の相対誤差か最初に見つけた違反である。
//!
//! 定数の環境で拡散照度が円周率×放射輝度・鏡面畳込みがどの粗さ段も放射輝度そのものになることは、
//! 標本の重みの規約が正しいことの証拠である。ばらつきの単調な減りは、粗さが標本の広がりへ効いていることの証拠である。
//!
//! ばらつきの減りだけ真であることを課すで表すのは、この判定が前の段と等しい値を破れの側へ置くためである。
//! 上限の口は等しい値を通すため、そのまま置き換えると、どの段も同じ画像を作る実装が境界でだけ通る。

use super::super::rows::報告;
use super::super::thresholds::定数環境の相対許容;
use crate::acceptance::{判定の名前, 判定の破れ};

const 定数環境の行: 判定の名前 = 判定の名前::定数から生成する("報告の定数環境の行");
const ばらつきの行数: 判定の名前 = 判定の名前::定数から生成する("鏡面段ばらつきの行数");

/// 段の並びを見るのに要る最小の本数。1本では前の段との比べが1度も起きない。
const ばらつきに要る行数: usize = 2;

pub(super) fn 定数環境を検査する(報告: &報告) -> Result<f64, 判定の破れ> {
    if 報告.定数環境拡散.is_empty() || 報告.定数環境鏡面.is_empty() {
        return Err(定数環境の行.あるはずのものが無い破れ());
    }
    let mut 最大 = 0.0_f64;
    for (名前, 一覧) in [("拡散", &報告.定数環境拡散), ("鏡面", &報告.定数環境鏡面)] {
        for 行 in 一覧.iter() {
            定数環境の判定名(名前, 行.放射輝度緑, 行.段).上限を課す(行.最大相対誤差, 定数環境の相対許容)?;
            最大 = 最大.max(行.最大相対誤差);
        }
    }
    Ok(最大)
}

/// 段の番号が増えるほどばらつきが減ることを見る。等しい値も違反にするのは、粗さを読み落とした実装が
/// どの段も同じ画像を作り、ばらつきが完全に一致するためである。
pub(super) fn ばらつきの単調な減りを検査する(報告: &報告) -> Result<(), 判定の破れ> {
    ばらつきの行数.下限を課す(報告.分散.len(), ばらつきに要る行数)?;
    let mut 前 = f64::INFINITY;
    for 行 in &報告.分散 {
        ばらつきの減りの判定名(行.段, 行.分散, 前).真であることを課す(行.分散 < 前)?;
        前 = 行.分散;
    }
    Ok(())
}

fn 定数環境の判定名(名前: &str, 放射輝度緑: f64, 段: u32) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("定数環境(放射輝度緑{放射輝度緑})の{名前}の段{段}の最大相対誤差"))
}

/// 2つのばらつきを綴りへ入れるのは、真偽で課す判定が比べた数を文面へ出せないためである。
fn ばらつきの減りの判定名(段: u32, ばらつき: f64, 前の段のばらつき: f64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("段{段}のばらつき{ばらつき:.3e}が前の段の{前の段のばらつき:.3e}より小さいこと"))
}
