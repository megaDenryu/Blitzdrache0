//! 解析的に答えが決まる項目の判定。受け取るのは報告、返すのは最大の相対誤差か最初に見つけた違反である。
//!
//! 定数の環境で拡散照度が円周率×放射輝度・鏡面畳込みがどの粗さ段も放射輝度そのものになることは、
//! 標本の重みの規約が正しいことの証拠である。ばらつきの単調な減りは、粗さが標本の広がりへ効いていることの証拠である。

use super::super::rows::報告;
use super::super::thresholds::定数環境の相対許容;

pub(super) fn 定数環境を検査する(報告: &報告) -> Result<f64, String> {
    if 報告.定数環境拡散.is_empty() || 報告.定数環境鏡面.is_empty() {
        return Err("報告に定数環境の行が無い".to_string());
    }
    let mut 最大 = 0.0_f64;
    for (名前, 一覧) in [("拡散", &報告.定数環境拡散), ("鏡面", &報告.定数環境鏡面)] {
        for 行 in 一覧.iter() {
            if 行.最大相対誤差 > 定数環境の相対許容 {
                return Err(format!(
                    "定数環境(放射輝度緑{})の{名前}の段{}の最大相対誤差{:.3e}が許容{定数環境の相対許容:.1e}を超えた",
                    行.放射輝度緑, 行.段, 行.最大相対誤差
                ));
            }
            最大 = 最大.max(行.最大相対誤差);
        }
    }
    Ok(最大)
}

/// 段の番号が増えるほどばらつきが減ることを見る。等しい値も違反にするのは、粗さを読み落とした実装が
/// どの段も同じ画像を作り、ばらつきが完全に一致するためである。
pub(super) fn ばらつきの単調な減りを検査する(報告: &報告) -> Result<(), String> {
    if 報告.分散.len() < 2 {
        return Err(format!("鏡面段ばらつきの行が{}件しかない", 報告.分散.len()));
    }
    let mut 前 = f64::INFINITY;
    for 行 in &報告.分散 {
        if 行.分散 >= 前 {
            return Err(format!("段{}のばらつき{:.3e}が前の段の{前:.3e}以上である", 行.段, 行.分散));
        }
        前 = 行.分散;
    }
    Ok(())
}
