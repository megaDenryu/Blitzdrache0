//! 全テクセルの健全性・最詳細段の複製・面境界の連続性の判定。受け取るのは報告、
//! 返すのは面境界の相対差に一辺を掛けた値の最大か、最初に見つけた違反である。
//!
//! 一辺を掛けた値を返すのは、段ごとに一辺が違い、相対差そのものを段どうしで比べても意味が無いためである。
//! 掛けた後の値は「テクセル1つの角あたりの変化」であり、段が違っても同じ尺度で読める。

use super::super::rows::報告;
use super::super::thresholds::面境界の相対許容;

/// 見る種別。3つそろっていることも同時に確かめる。
const 期待する統計の種別: [&str; 3] = ["拡散", "鏡面", "反射率積分表"];

pub(super) fn 健全性を検査する(報告: &報告) -> Result<(), String> {
    for 種別 in 期待する統計の種別 {
        let Some(行) = 報告.統計.iter().find(|行| 行.種別 == 種別) else {
            return Err(format!("報告に種別{種別}の統計の行が無い"));
        };
        if 行.テクセル数 == 0 {
            return Err(format!("{種別}のテクセル数が0である"));
        }
        let 破れ一覧 = [("非有限", 行.非有限), ("負", 行.負), ("4成分目が非零", 行.予約が非零)];
        for (名前, 件数) in 破れ一覧 {
            if 件数 != 0 {
                return Err(format!("{種別}に{名前}のテクセルが{件数}件あった"));
            }
        }
    }
    Ok(())
}

pub(super) fn 最詳細段の複製を検査する(報告: &報告) -> Result<(), String> {
    let Some(不一致) = 報告.最詳細段の不一致 else {
        return Err("報告に鏡面最詳細段の行が無い".to_string());
    };
    if 不一致 != 0 {
        return Err(format!("鏡面畳込みの最詳細段が遠方環境と{不一致}テクセル違う(複製になっていない)"));
    }
    Ok(())
}

pub(super) fn 面境界を検査する(報告: &報告) -> Result<f64, String> {
    if 報告.面境界.is_empty() {
        return Err("報告に派生表現面境界の行が無い".to_string());
    }
    let mut 最大 = 0.0_f64;
    for 行 in &報告.面境界 {
        if 行.稜線数 != 12 {
            return Err(format!("{}の段{}の稜線数が{}件で、立方体の12本と違う", 行.種別, 行.段, 行.稜線数));
        }
        let 許容 = 面境界の相対許容(行.一辺);
        if 行.最大相対差 > 許容 {
            return Err(format!(
                "{}の段{}(一辺{})の面境界の最大相対差{:.3e}が許容{許容:.1e}を超えた",
                行.種別, 行.段, 行.一辺, 行.最大相対差
            ));
        }
        最大 = 最大.max(行.最大相対差 * f64::from(行.一辺));
    }
    Ok(最大)
}
