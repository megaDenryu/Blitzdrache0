//! 全テクセルの健全性・最詳細段の複製・面境界の連続性の判定。受け取るのは報告、
//! 返すのは面境界の相対差に一辺を掛けた値の最大か、最初に見つけた違反である。
//!
//! 一辺を掛けた値を返すのは、段ごとに一辺が違い、相対差そのものを段どうしで比べても意味が無いためである。
//! 掛けた後の値は「テクセル1つの角あたりの変化」であり、段が違っても同じ尺度で読める。

use super::super::rows::報告;
use super::super::thresholds::面境界の相対許容;
use crate::acceptance::{判定の名前, 判定の破れ};

/// 見る種別。3つそろっていることも同時に確かめる。
const 期待する統計の種別: [&str; 3] = ["拡散", "鏡面", "反射率積分表"];
/// 立方体の稜線の本数。面境界の行はこの本数を突き合わせたものでなければならない。
const 立方体の稜線数: usize = 12;

const 最詳細段の行: 判定の名前 = 判定の名前::定数から生成する("報告の鏡面最詳細段の行");
const 最詳細段の複製の不一致: 判定の名前 =
    判定の名前::定数から生成する("鏡面畳込みの最詳細段が遠方環境と違うテクセル(複製になっていない)");
const 面境界の行: 判定の名前 = 判定の名前::定数から生成する("報告の派生表現面境界の行");

pub(super) fn 健全性を検査する(報告: &報告) -> Result<(), 判定の破れ> {
    for 種別 in 期待する統計の種別 {
        let Some(行) = 報告.統計.iter().find(|行| 行.種別 == 種別) else {
            return Err(判定名を組む(&format!("報告の種別{種別}の統計の行")).あるはずのものが無い破れ());
        };
        if 行.テクセル数 == 0 {
            return Err(判定名を組む(&format!("{種別}のテクセル")).あるはずのものが無い破れ());
        }
        let 破れ一覧 = [("非有限", 行.非有限), ("負", 行.負), ("4成分目が非零", 行.予約が非零)];
        for (名前, 件数) in 破れ一覧 {
            判定名を組む(&format!("{種別}の{名前}のテクセル")).零件であることを課す(件数)?;
        }
    }
    Ok(())
}

pub(super) fn 最詳細段の複製を検査する(報告: &報告) -> Result<(), 判定の破れ> {
    let Some(不一致) = 報告.最詳細段の不一致 else {
        return Err(最詳細段の行.あるはずのものが無い破れ());
    };
    最詳細段の複製の不一致.零件であることを課す(不一致)
}

pub(super) fn 面境界を検査する(報告: &報告) -> Result<f64, 判定の破れ> {
    if 報告.面境界.is_empty() {
        return Err(面境界の行.あるはずのものが無い破れ());
    }
    let mut 最大 = 0.0_f64;
    for 行 in &報告.面境界 {
        判定名を組む(&format!("{}の段{}の稜線数", 行.種別, 行.段)).一致を課す(行.稜線数, 立方体の稜線数)?;
        判定名を組む(&format!("{}の段{}(一辺{})の面境界の最大相対差", 行.種別, 行.段, 行.一辺))
            .上限を課す(行.最大相対差, 面境界の相対許容(行.一辺))?;
        最大 = 最大.max(行.最大相対差 * f64::from(行.一辺));
    }
    Ok(最大)
}

fn 判定名を組む(綴り: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(綴り.to_string())
}
