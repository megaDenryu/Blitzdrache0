//! 代表テクセルとCPU正本の突き合わせ。受け取るのは報告、返すのは最大の相対誤差か最初に許容を超えた場所である。
//!
//! 期待の絶対値が小さい成分を相対誤差で見ないのは、分母が0に近いと相対誤差が発散するためである。
//!
//! 反射率積分表の許容を行ごとに変えるのは、粗さが最も小さい行だけが単精度の限界で大きくずれるためである。
//! 一律に緩い許容を置くと、実測が桁違いに小さい残りの行が悪化しても検査が通ってしまう。

use super::super::rows::報告;
use super::super::thresholds::{代表の相対許容, 代表の絶対許容, 反射率積分表の相対許容};

pub(super) fn 代表テクセルを検査する(報告: &報告) -> Result<f64, String> {
    if 報告.代表.is_empty() || 報告.反射率積分表代表.is_empty() {
        return Err("報告に代表テクセルの行が無い".to_string());
    }
    let mut 最大 = 0.0_f64;
    for 行 in &報告.代表 {
        for 添字 in 0..3 {
            let 場所 = format!("派生表現代表({} 段{} 層{} 横{} 縦{} 成分{添字})", 行.種別, 行.段, 行.層, 行.横, 行.縦);
            最大 = 最大.max(誤差を見る(行.期待[添字], 行.実測[添字], 代表の相対許容, &場所)?);
        }
    }
    for 行 in &報告.反射率積分表代表 {
        let 許容 = 反射率積分表の相対許容(行.縦);
        for 添字 in 0..2 {
            let 場所 = format!("反射率積分表代表(横{} 縦{} 成分{添字})", 行.横, 行.縦);
            最大 = 最大.max(誤差を見る(行.期待[添字], 行.実測[添字], 許容, &場所)?);
        }
    }
    Ok(最大)
}

fn 誤差を見る(期待: f64, 実測: f64, 相対許容: f64, 場所: &str) -> Result<f64, String> {
    let 差 = (期待 - 実測).abs();
    if 期待.abs() <= 代表の絶対許容 {
        if 差 > 代表の絶対許容 {
            return Err(format!("{場所}の絶対誤差{差:.3e}が許容{代表の絶対許容:.1e}を超えた"));
        }
        return Ok(0.0);
    }
    let 相対 = 差 / 期待.abs();
    if 相対 > 相対許容 {
        return Err(format!("{場所}の相対誤差{相対:.3e}が許容{相対許容:.1e}を超えた"));
    }
    Ok(相対)
}
