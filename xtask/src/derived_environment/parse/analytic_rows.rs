//! 解析解と突き合わせる行の見出しと読み方。受け取るのは終了時報告、返すのは定数の環境1つぶんの行の一覧である。
//!
//! 拡散と鏡面で口を分けるのは、鏡面の行だけが段を持つためである。1つの口へまとめると、段を持たない行から
//! 段を読もうとして「段の鍵が無い」で落ちる。

use crate::acceptance::{検収エラー, 終了時報告};
use crate::distant_environment::parse::field::{実数値, 添字値};
use crate::report_heading::報告の見出し;

use super::super::rows::定数環境行;

const 定数環境拡散の見出し: 報告の見出し = 報告の見出し::定数から生成する("定数環境拡散");
const 定数環境鏡面の見出し: 報告の見出し = 報告の見出し::定数から生成する("定数環境鏡面");

/// 拡散の行は段を持たないため0で埋める。1つの型で拡散と鏡面を並べて読めるようにするためである。
pub(super) fn 拡散の一覧を読む(終了時の報告: &終了時報告) -> Result<Vec<定数環境行>, 検収エラー> {
    終了時の報告
        .見出しで始まる行の一覧(&定数環境拡散の見出し)
        .iter()
        .map(|行| {
            Ok(定数環境行 {
                放射輝度緑: 実数値(行, "放射輝度緑")?,
                段: 0,
                最大相対誤差: 実数値(行, "最大相対誤差")?,
            })
        })
        .collect()
}

pub(super) fn 鏡面の一覧を読む(終了時の報告: &終了時報告) -> Result<Vec<定数環境行>, 検収エラー> {
    終了時の報告
        .見出しで始まる行の一覧(&定数環境鏡面の見出し)
        .iter()
        .map(|行| {
            Ok(定数環境行 {
                放射輝度緑: 実数値(行, "放射輝度緑")?,
                段: 添字値(行, "段")?,
                最大相対誤差: 実数値(行, "最大相対誤差")?,
            })
        })
        .collect()
}
