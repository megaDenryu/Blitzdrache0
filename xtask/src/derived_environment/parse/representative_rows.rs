//! 代表テクセルの行の見出しと読み方。受け取るのは終了時報告、返すのは代表テクセルの行の一覧である。
//!
//! 派生表現の代表と反射率積分表の代表で口を分けるのは、持つ成分の数と鍵の綴りが違うためである。
//! 立方体の代表は層と横と縦を持つ3成分、反射率積分表の代表は横と縦だけを持つ2成分である。

use crate::acceptance::{報告の行, 検収エラー, 終了時報告};
use crate::distant_environment::parse::field::{実数値, 添字値, 語句値};
use crate::report_heading::報告の見出し;

use super::super::rows::{代表行, 反射率積分表行};

const 派生表現代表の見出し: 報告の見出し = 報告の見出し::定数から生成する("派生表現代表");
const 反射率積分表代表の見出し: 報告の見出し = 報告の見出し::定数から生成する("反射率積分表代表");

pub(super) fn 派生表現の代表の一覧を読む(終了時の報告: &終了時報告) -> Result<Vec<代表行>, 検収エラー> {
    終了時の報告
        .見出しで始まる行の一覧(&派生表現代表の見出し)
        .iter()
        .map(代表行を読む)
        .collect()
}

pub(super) fn 反射率積分表の代表の一覧を読む(
    終了時の報告: &終了時報告
) -> Result<Vec<反射率積分表行>, 検収エラー> {
    終了時の報告
        .見出しで始まる行の一覧(&反射率積分表代表の見出し)
        .iter()
        .map(反射率積分表行を読む)
        .collect()
}

fn 代表行を読む(行: &報告の行) -> Result<代表行, 検収エラー> {
    Ok(代表行 {
        種別: 語句値(行, "種別")?,
        段: 添字値(行, "段")?,
        層: 添字値(行, "層")?,
        横: 添字値(行, "横")?,
        縦: 添字値(行, "縦")?,
        期待: [実数値(行, "期待赤")?, 実数値(行, "期待緑")?, 実数値(行, "期待青")?],
        実測: [実数値(行, "実測赤")?, 実数値(行, "実測緑")?, 実数値(行, "実測青")?],
    })
}

fn 反射率積分表行を読む(行: &報告の行) -> Result<反射率積分表行, 検収エラー> {
    Ok(反射率積分表行 {
        横: 添字値(行, "横")?,
        縦: 添字値(行, "縦")?,
        期待: [実数値(行, "期待倍率")?, 実数値(行, "期待加算")?],
        実測: [実数値(行, "実測倍率")?, 実数値(行, "実測加算")?],
    })
}
