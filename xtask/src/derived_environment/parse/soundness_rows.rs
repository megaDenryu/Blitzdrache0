//! 全テクセルの健全性・粗さごとのばらつき・最詳細段の複製・面境界の連続性を見る行の見出しと読み方。
//! 受け取るのは終了時報告、返すのはそれぞれの行の一覧である。
//!
//! 最詳細段だけ一覧でなく1つの値を返すのは、報告がこの行を1本しか出さないためである。行が無いことは
//! 失敗と読み替えず、無いことを返す。焼き上げが1度も走らなかった実行を判定が名指すためである。

use crate::acceptance::{報告の行, 検収エラー, 終了時報告};
use crate::distant_environment::parse::field::{実数値, 整数値, 添字値, 語句値};
use crate::report_heading::報告の見出し;

use super::super::rows::{分散行, 統計行, 面境界行};

const 統計の見出し: 報告の見出し = 報告の見出し::定数から生成する("派生表現統計");
const ばらつきの見出し: 報告の見出し = 報告の見出し::定数から生成する("鏡面段ばらつき");
const 最詳細段の見出し: 報告の見出し = 報告の見出し::定数から生成する("鏡面最詳細段");
const 面境界の見出し: 報告の見出し = 報告の見出し::定数から生成する("派生表現面境界");

pub(super) fn 統計の一覧を読む(終了時の報告: &終了時報告) -> Result<Vec<統計行>, 検収エラー> {
    終了時の報告.見出しで始まる行の一覧(&統計の見出し).iter().map(統計行を読む).collect()
}

pub(super) fn ばらつきの一覧を読む(終了時の報告: &終了時報告) -> Result<Vec<分散行>, 検収エラー> {
    終了時の報告.見出しで始まる行の一覧(&ばらつきの見出し).iter().map(分散行を読む).collect()
}

pub(super) fn 面境界の一覧を読む(終了時の報告: &終了時報告) -> Result<Vec<面境界行>, 検収エラー> {
    終了時の報告.見出しで始まる行の一覧(&面境界の見出し).iter().map(面境界行を読む).collect()
}

pub(super) fn 最詳細段の不一致を読む(終了時の報告: &終了時報告) -> Result<Option<usize>, 検収エラー> {
    終了時の報告
        .見出しで始まる行の一覧(&最詳細段の見出し)
        .first()
        .map(|行| 整数値(行, "不一致"))
        .transpose()
}

fn 統計行を読む(行: &報告の行) -> Result<統計行, 検収エラー> {
    Ok(統計行 {
        種別: 語句値(行, "種別")?,
        テクセル数: 整数値(行, "テクセル数")?,
        非有限: 整数値(行, "非有限")?,
        負: 整数値(行, "負")?,
        予約が非零: 整数値(行, "予約が非零")?,
    })
}

fn 分散行を読む(行: &報告の行) -> Result<分散行, 検収エラー> {
    Ok(分散行 {
        段: 添字値(行, "段")?,
        分散: 実数値(行, "分散")?,
    })
}

fn 面境界行を読む(行: &報告の行) -> Result<面境界行, 検収エラー> {
    Ok(面境界行 {
        種別: 語句値(行, "種別")?,
        段: 添字値(行, "段")?,
        一辺: 添字値(行, "一辺")?,
        稜線数: 整数値(行, "稜線数")?,
        最大相対差: 実数値(行, "最大相対差")?,
    })
}
