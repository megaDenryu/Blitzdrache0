//! 派生表現報告の全文から、判定に要る行だけを取り出す工程。受け取るのは標準出力、返すのは行の値を組んだ報告である。
//!
//! 行の形をここが単独で持つのは、これがblitz_appとxtaskの間の機械可読な契約そのものだからである。
//! 語の並びに依存せず鍵で参照するのは、報告へ項目を足したときに読み取り側が壊れないようにするためである。
//! 行の値の取り出しは遠方環境の検収が持つ`field`を共有する。

use crate::distant_environment::parse::field::{実数値, 整数値, 添字値, 語句値};

use super::rows::{代表行, 分散行, 反射率積分表行, 報告, 定数環境行, 統計行, 面境界行};

pub(super) fn 報告を取り出す(標準出力: &str) -> Result<報告, String> {
    let mut 報告 = 報告::空();
    for 行 in 標準出力.lines() {
        let 語一覧: Vec<&str> = 行.split_whitespace().collect();
        match 語一覧.first().copied() {
            Some("検証層") => 報告.検証 = Some((語句値(&語一覧, "状況")?, 整数値(&語一覧, "件数")?)),
            Some("定数環境拡散") => 報告.定数環境拡散.push(定数環境行 {
                放射輝度緑: 実数値(&語一覧, "放射輝度緑")?,
                段: 0,
                最大相対誤差: 実数値(&語一覧, "最大相対誤差")?,
            }),
            Some("定数環境鏡面") => 報告.定数環境鏡面.push(定数環境行 {
                放射輝度緑: 実数値(&語一覧, "放射輝度緑")?,
                段: 添字値(&語一覧, "段")?,
                最大相対誤差: 実数値(&語一覧, "最大相対誤差")?,
            }),
            Some("派生表現統計") => 報告.統計.push(統計行 {
                種別: 語句値(&語一覧, "種別")?,
                テクセル数: 整数値(&語一覧, "テクセル数")?,
                非有限: 整数値(&語一覧, "非有限")?,
                負: 整数値(&語一覧, "負")?,
                予約が非零: 整数値(&語一覧, "予約が非零")?,
            }),
            Some("鏡面段ばらつき") => 報告.分散.push(分散行 {
                段: 添字値(&語一覧, "段")?,
                分散: 実数値(&語一覧, "分散")?,
            }),
            Some("鏡面最詳細段") => 報告.最詳細段の不一致 = Some(整数値(&語一覧, "不一致")?),
            Some("派生表現面境界") => 報告.面境界.push(面境界行 {
                種別: 語句値(&語一覧, "種別")?,
                段: 添字値(&語一覧, "段")?,
                一辺: 添字値(&語一覧, "一辺")?,
                稜線数: 整数値(&語一覧, "稜線数")?,
                最大相対差: 実数値(&語一覧, "最大相対差")?,
            }),
            Some("派生表現代表") => 報告.代表.push(代表行を読む(&語一覧)?),
            Some("反射率積分表代表") => 報告.反射率積分表代表.push(反射率積分表行 {
                横: 添字値(&語一覧, "横")?,
                縦: 添字値(&語一覧, "縦")?,
                期待: [実数値(&語一覧, "期待倍率")?, 実数値(&語一覧, "期待加算")?],
                実測: [実数値(&語一覧, "実測倍率")?, 実数値(&語一覧, "実測加算")?],
            }),
            _ => {}
        }
    }
    Ok(報告)
}

fn 代表行を読む(語一覧: &[&str]) -> Result<代表行, String> {
    Ok(代表行 {
        種別: 語句値(語一覧, "種別")?,
        段: 添字値(語一覧, "段")?,
        層: 添字値(語一覧, "層")?,
        横: 添字値(語一覧, "横")?,
        縦: 添字値(語一覧, "縦")?,
        期待: [実数値(語一覧, "期待赤")?, 実数値(語一覧, "期待緑")?, 実数値(語一覧, "期待青")?],
        実測: [実数値(語一覧, "実測赤")?, 実数値(語一覧, "実測緑")?, 実数値(語一覧, "実測青")?],
    })
}
