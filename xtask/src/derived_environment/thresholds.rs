//! 派生表現の判定に使う許容と期待の台帳。担当するのは値だけであり、判定の手順は`judgment`が持つ。
//!
//! 定数環境の許容が半精度の丸め(相対4.9e-4まで)より少し大きいのは、GPUが標本の総和を単精度で積み、
//! 結果をもう一度半精度で書くためである。定数の環境では標本ごとの値がすべて等しく、積算の誤差は
//! 標本数の平方根に比例する程度にとどまる。
//!
//! 代表テクセルの許容がそれより大きいのは、CPUが倍精度で三角関数と平方根を評価するのに対し、GPUが単精度で
//! 評価するためである。向きのわずかな違いが1テクセルの参照先を変えうるため、標本のうち数個が隣のテクセルを
//! 読むことがある。実測は報告の要約に出る。

/// 定数の環境で拡散照度と鏡面畳込みが解析解と一致すべき相対許容。
pub(super) const 定数環境の相対許容: f64 = 5.0e-3;

/// 代表テクセルのCPU正本との相対誤差の許容。
pub(super) const 代表の相対許容: f64 = 5.0e-2;

/// ほぼ0の域で相対誤差の代わりに見る絶対誤差の許容。分母が小さいと相対誤差が発散するためである。
pub(super) const 代表の絶対許容: f64 = 1.0e-4;

/// 反射率積分表の代表テクセルの相対許容を、そのテクセルの縦の添字から求める。
///
/// 粗さが最も小さい行だけを緩め、残りを狭く保つのは検査の感度のためである。一律に緩い許容を置くと、
/// 実測が5e-4以下の行が2パーセントまで悪化しても検査が通ってしまう。
///
/// 粗さが最も小さい行が緩いのは、粗さ0.00195で法線分布の広がりの二乗が1.5e-11になり、単精度では1との差を
/// 1つも表せないためである。GPUは半ベクトルの傾きを完全に失って法線そのものを標本する一方、倍精度で計算する
/// 正本はこの傾きを解けるため、視線が面に近い側で標本ごとの重みが1パーセント弱ずれる。
/// これは写しの誤りでなく、粗さ0へ近づく極での単精度の限界である。
///
/// 2026-08-03の実測は、粗さが最も小さい行が9.145e-3、それ以外の行が6.567e-4である。
/// 許容はそれぞれ約2.2倍と約3.0倍の安全幅を取った値である。
pub(super) fn 反射率積分表の相対許容(縦: u32) -> f64 {
    if 縦 == 0 {
        return 粗さが最も小さい行の相対許容;
    }
    反射率積分表の通常の相対許容
}

const 粗さが最も小さい行の相対許容: f64 = 2.0e-2;
const 反射率積分表の通常の相対許容: f64 = 2.0e-3;

/// 面境界の相対差の許容を一辺から求める。許容を一辺に反比例させるのは、稜線をはさんで向かい合う2つのテクセルが
/// 1テクセルぶんの角だけ離れており、その角が一辺に反比例するためである。焼いた量が向きについて滑らかである限り、
/// 差は角に比例する。一定の許容にすると、粗い段(4テクセル四方の面は1テクセルが22.5度を覆う)で
/// 意味のある判定ができなくなる。
///
/// 係数は2026-08-03の実測から取った。方向性の強い環境での実測は一辺128で3.48e-2、64で7.09e-2、32で9.71e-2、
/// 16で1.52e-1、8で2.61e-1、4で4.62e-1であり、一辺を掛けた値の最大は4.54である。係数はその約1.8倍を取る。
pub(super) fn 面境界の相対許容(一辺: u32) -> f64 {
    面境界の許容係数 / f64::from(一辺)
}

const 面境界の許容係数: f64 = 8.0;

/// validation層が有効だったことを表す語。これ以外の語では件数0が保証にならないため、その事実を告知する。
pub(super) const 検証層が有効な語: &str = "有効";
