//! 実行時形式を焼く指定と、その組み立て。担当するのは「1回の焼き付けが何をどう焼くか」を1つの値として持つことだけであり、
//! 起動そのものは`invoke`が持つ。
//!
//! 必須の3つ(ソースの置き場・出力の置き場・世界)を構築の口で受け、任意の4つをメソッドの連鎖で足すビルダーにする。
//! 7つを1つの関数の引数へ並べると、同じ型の任意の指定どうしを取り違えても署名が通る。既定は「同居植生も格納方針も
//! 生成器側の既定に任せ、遠景地形は焼かず、散布は焼く」である。散布だけが既定で焼く側なのは、散布が世界の絵の一部であり、
//! 焼かない側を選ぶのは絵の対照を採る検収だけだからである。
//!
//! 注意: 役割として保持するだけの構築であるため、失敗も副作用も持たない。出力ディレクトリを作るのはそこへ
//! 書き出す生成器の側であり、指定を組むだけで作ると、生成器を1度も起こせなかった実行が空のディレクトリを残す。

use std::path::Path;

use blitz_asset_compiler::{
    ソースルート, テクスチャ格納方針, 実行時形式の出力ルート, 散布の焼き方, 遠景地形の焼き方
};

use crate::asset_generator::{世界名, 同居植生の個体数, 生成の指定};

/// コンパイラの入口が受け取る指定一式。
pub(super) struct 実行時形式を焼く指定 {
    pub(super) ソースルート: ソースルート,
    pub(super) 出力ルート: 実行時形式の出力ルート,
    pub(super) 世界: 世界名,
    pub(super) 同居植生個体数: Option<同居植生の個体数>,
    pub(super) テクスチャ格納方針: Option<テクスチャ格納方針>,
    pub(super) 遠景地形: 遠景地形の焼き方,
    pub(super) 散布: 散布の焼き方,
}

impl 実行時形式を焼く指定 {
    pub(super) fn 始める(ソースの置き場: &Path, 出力の置き場: &Path, 世界: 世界名) -> Self {
        Self {
            ソースルート: ソースルート::生成する(ソースの置き場.to_path_buf()),
            出力ルート: 実行時形式の出力ルート::ディレクトリを作らずに指す(出力の置き場.to_path_buf()),
            世界,
            同居植生個体数: None,
            テクスチャ格納方針: None,
            遠景地形: 遠景地形の焼き方::焼かない,
            散布: 散布の焼き方::焼く,
        }
    }

    pub(super) fn 同居植生個体数を足す(mut self, 個体数: Option<同居植生の個体数>) -> Self {
        self.同居植生個体数 = 個体数;
        self
    }

    pub(super) fn テクスチャ格納方針を足す(mut self, 方針: Option<テクスチャ格納方針>) -> Self {
        self.テクスチャ格納方針 = 方針;
        self
    }

    pub(super) fn 遠景地形の焼き方を選ぶ(mut self, 焼き方: 遠景地形の焼き方) -> Self {
        self.遠景地形 = 焼き方;
        self
    }

    pub(super) fn 散布の焼き方を選ぶ(mut self, 焼き方: 散布の焼き方) -> Self {
        self.散布 = 焼き方;
        self
    }

    /// 生成器を起こす器が受け取る形へ写す。写しをここが持つのは、どの欄がどの引数になるかがこの型の
    /// 持ち物の並びそのものだからである。
    pub(super) fn 生成の指定へ写す(&self) -> 生成の指定<'_> {
        生成の指定::実行時形式を焼く {
            ソースルート: &self.ソースルート,
            出力ルート: &self.出力ルート,
            世界: self.世界,
            同居植生個体数: self.同居植生個体数,
            テクスチャ格納方針: self.テクスチャ格納方針,
            遠景地形: self.遠景地形,
            散布: self.散布,
        }
    }
}
