//! アセットコンパイラのexampleをプロセスとして起動する工程。受け取るのは焼く指定、返すのは成否である。
//!
//! 起動そのものを親モジュールから分けるのは、これから焼く対象を告げる文面が親の持つ
//! 「どの世界をどの出力ルートへ焼くか」の対応と別の関心事だからである。
//! 起こし方と引数の組み立ては`asset_generator`の器が持ち、焼く指定の組み立ては`bake_specification`が持つ。

use super::bake_specification::実行時形式を焼く指定;
use super::texture_policy_name::方針の呼び名;
use crate::asset_generator::{アセット生成器の起動, 生成器エラー};

/// 標準出力を取り込んで返す形で焼く。増分が効いたかを外から見る材料が、コンパイラの報告の行だけであるためである。
pub(super) fn アセットコンパイラを起動して標準出力を取り込む(
    指定: &実行時形式を焼く指定,
) -> Result<String, 生成器エラー> {
    これから焼く対象を告げる(指定);
    アセット生成器の起動::始める(&指定.生成の指定へ写す())?.走らせて標準出力を取り込む()
}

pub(super) fn アセットコンパイラを起動して実行時形式を焼く(指定: &実行時形式を焼く指定) -> bool {
    これから焼く対象を告げる(指定);
    match 焼かせる(指定) {
        Ok(()) => true,
        Err(理由) => {
            eprintln!("[xtask] 実行時アセット生成に失敗した: {理由}");
            false
        }
    }
}

fn 焼かせる(指定: &実行時形式を焼く指定) -> Result<(), 生成器エラー> {
    アセット生成器の起動::始める(&指定.生成の指定へ写す())?.画面へ流したまま走らせて終わりを待つ()
}

/// 注意: 行に出す値はどれも人へ見せる口(`表示の綴り`と`Display`)から採る。生成器の引数へ戻す口は
/// 器の内側だけのものであり、報告へ流用すると閉じたはずの生値化がここから漏れる。
fn これから焼く対象を告げる(指定: &実行時形式を焼く指定) {
    println!(
        "[xtask] 実行時アセット生成({}{}{}): {} -> {}",
        指定.世界,
        指定.同居植生個体数.map_or_else(String::new, |個体数| format!(", 同居植生{個体数}体")),
        指定
            .テクスチャ格納方針
            .map_or_else(String::new, |方針| format!(", 格納方針{}", 方針の呼び名(方針))),
        指定.ソースルート.表示の綴り(),
        指定.出力ルート.表示の綴り()
    );
}
