//! アセットコンパイラのexampleをプロセスとして起動する工程。受け取るのはソースルートと出力ルートと世界名と、
//! 世界によっては要る同居植生の個体数とテクスチャ格納方針の名前、返すのは成否である。
//!
//! 起動そのものを親モジュールから分けるのは、これから焼く対象を告げる文面が親の持つ
//! 「どの世界をどの出力ルートへ焼くか」の対応と別の関心事だからである。
//! 起こし方と引数の組み立ては`asset_generator`の器が持つ。

use std::path::Path;

use crate::asset_generator::世界名;
use crate::asset_generator::{アセット生成器の起動, 生成の指定};

/// コンパイラの入口が受け取る指定一式。方針の名前を渡さない呼び出しは、コンパイラ側の既定(`全てRGBA8`)で焼かれる。
pub(super) struct 実行時形式を焼く指定<'指定> {
    pub(super) ソースルート: &'指定 Path,
    pub(super) 出力ルート: &'指定 Path,
    pub(super) 世界: 世界名,
    pub(super) 同居植生個体数: Option<&'指定 str>,
    pub(super) テクスチャ格納方針の名前: Option<&'指定 str>,
}

impl 実行時形式を焼く指定<'_> {
    fn 生成の指定へ写す(&self) -> 生成の指定<'_> {
        生成の指定::実行時形式を焼く {
            ソースルート: self.ソースルート,
            出力ルート: self.出力ルート,
            世界: self.世界,
            同居植生個体数: self.同居植生個体数,
            テクスチャ格納方針の名前: self.テクスチャ格納方針の名前,
        }
    }
}

/// 標準出力を取り込んで返す形で焼く。増分が効いたかを外から見る材料が、コンパイラの報告の行だけであるためである。
pub(super) fn アセットコンパイラを起動して標準出力を取り込む(
    指定: &実行時形式を焼く指定
) -> Result<String, String> {
    これから焼く対象を告げる(指定);
    Ok(アセット生成器の起動::始める(&指定.生成の指定へ写す())?.走らせて標準出力を取り込む()?)
}

pub(super) fn アセットコンパイラを起動して実行時形式を焼く(指定: &実行時形式を焼く指定) -> bool {
    これから焼く対象を告げる(指定);
    match 焼かせる(指定) {
        Ok(()) => true,
        Err(理由) => {
            eprintln!("[xtask] 実行時アセット生成に失敗した: {理由}");
            false
        }
    }
}

fn 焼かせる(指定: &実行時形式を焼く指定) -> Result<(), crate::asset_generator::生成器エラー> {
    アセット生成器の起動::始める(&指定.生成の指定へ写す())?.画面へ流したまま走らせて終わりを待つ()
}

fn これから焼く対象を告げる(指定: &実行時形式を焼く指定) {
    println!(
        "[xtask] 実行時アセット生成({}{}{}): {} -> {}",
        指定.世界,
        指定.同居植生個体数.map_or_else(String::new, |個体数| format!(", 同居植生{個体数}体")),
        指定.テクスチャ格納方針の名前.map_or_else(String::new, |名前| format!(", 格納方針{名前}")),
        指定.ソースルート.display(),
        指定.出力ルート.display()
    );
}
