//! プロセス境界でテクスチャ格納方針を指す綴りの台帳。担当するのは綴りそのものと、選択肢としての並べ方だけである。
//! 綴りはアセットコンパイラ側(`crates/blitz_asset_compiler/examples/compile_assets/texture_policy_argument.rs`)にも
//! 同じものがあり、食い違えば実行時アセット生成が「未知のテクスチャ格納方針である」で失敗する。
//!
//! xtaskは外部依存を持たない実行ファイルであり、コンパイラの`テクスチャ格納方針`の型をここへ持ち込めない。
//! そのため方針を綴りで持ち、判別はコンパイラ側の解析に任せる。

/// 方針の指定を導く選択肢の綴り。この綴りの直後の1語が方針の名前である。
const 選択肢の綴り: &str = "--texture-storage-policy";

/// 全てのテクスチャを非圧縮のRGBA8で焼く方針。既存の全入口が使う既定であり、明示的に渡すのは対照を撮る入口だけである。
pub const 全てRGBA8: &str = "all_rgba8";

/// ベースカラーだけをBC1で焼く方針。`cargo xtask texture-compression`だけがこれを渡す。
/// 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`「判断i」
pub const ベースカラーのブロック圧縮: &str = "block_compressed_base_color";

/// 方針の名前を、コンパイラの入口へ渡す2語の選択肢へ組み立てる。
pub(super) fn 方針の選択肢の2語を組み立てる(方針の名前: &str) -> [&str; 2] {
    [選択肢の綴り, 方針の名前]
}
