//! テクスチャ格納方針を人へ見せる呼び名。担当するのは方針の枝から呼び名を返すことだけである。
//!
//! 方針そのものは`blitz_asset_compiler`の`テクスチャ格納方針`が正本であり、生成器へ渡す綴りは
//! `asset_generator`の生成引数が持つ。ここが持つのは、画面へ出す行と検収の失敗の文面が方針を名指すための呼び名である。
//! 呼び名を生成器へ渡す綴りと同じにしてあるのは、人が見た行と実際に渡る語が食い違わないようにするためである。

use blitz_asset_compiler::テクスチャ格納方針;

/// 全てのテクスチャを非圧縮のRGBA8で焼く方針の呼び名。
pub const 全てRGBA8: &str = "all_rgba8";

/// ベースカラーだけをBC1で焼く方針の呼び名。`cargo xtask texture-compression`だけがこれを渡す。
/// 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`「判断i」
pub const ベースカラーのブロック圧縮: &str = "block_compressed_base_color";

pub fn 方針の呼び名(方針: テクスチャ格納方針) -> &'static str {
    match 方針 {
        テクスチャ格納方針::全てRGBA8 => 全てRGBA8,
        テクスチャ格納方針::ベースカラーのブロック圧縮 => ベースカラーのブロック圧縮,
    }
}
