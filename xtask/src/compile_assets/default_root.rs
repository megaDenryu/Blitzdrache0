//! 世界ごとの既定出力ルートと、その世界を既定の場所へ焼く入口。担当するのは「どの世界がどの出力ルートを占めるか」の
//! 対応だけであり、生成の手続きそのものは親モジュールが持つ。
//!
//! 世界ごとに出力ルートを分けるのは、1つの出力ルートが1つのカタログと1つのチャンク目録しか持てないためである。
//! 原点チャンクを占める世界どうしは同じ出力ルートへ同居できない。

use std::path::Path;

use super::{地形の世界, 板の世界, 植生の世界, 生成する, 目視見本の世界, 見本の集落の世界};

const 既定ソースルート: &str = "assets";
const 既定出力ルート: &str = "target/runtime_assets";
const 地形の既定出力ルート: &str = "target/terrain_assets";
const 植生の既定出力ルート: &str = "target/vegetation_assets";
const 見本の集落の既定出力ルート: &str = "target/village_assets";
const 目視見本の既定出力ルート: &str = "target/terrain_visual_assets";

pub fn ソースルート() -> &'static Path {
    Path::new(既定ソースルート)
}

pub fn 既定を生成する() -> bool {
    生成する(ソースルート(), Path::new(既定出力ルート), 板の世界)
}

/// 地形世界は板の世界と同じ座標を占めるため、同じ出力ルートへは同居できない。専用の既定出力ルートへ焼く。
pub fn 地形世界を既定で生成する() -> bool {
    生成する(ソースルート(), Path::new(地形の既定出力ルート), 地形の世界)
}

/// 植生世界も原点チャンクを占めるため、専用の既定出力ルートへ焼く。
pub fn 植生世界を既定で生成する() -> bool {
    生成する(ソースルート(), Path::new(植生の既定出力ルート), 植生の世界)
}

/// 見本の集落も原点チャンクを占めるため、専用の既定出力ルートへ焼く。
/// 引数なしの一括生成へ入れないのは、この世界の小物の原型が本体リポジトリの外にあるアセットリポジトリだけにあり、
/// それを持たない環境では焼けないためである。焼けない世界を一括生成へ入れると、アセットリポジトリを持たない環境で
/// 既存の検証が全部止まる。この世界を要るのは`village-draw`だけであり、そこが名指しで呼ぶ。
pub fn 見本の集落世界を既定で生成する() -> bool {
    生成する(ソースルート(), Path::new(見本の集落の既定出力ルート), 見本の集落の世界)
}

/// 目視見本も原点チャンクを占めるため、専用の既定出力ルートへ焼く。一括生成へ入れない理由は見本の集落と同じであり、
/// 小物の原型が本体リポジトリの外にあるアセットリポジトリだけにある。この世界を要るのは`terrain-visual`だけである。
pub fn 目視見本世界を既定で生成する() -> bool {
    生成する(ソースルート(), Path::new(目視見本の既定出力ルート), 目視見本の世界)
}
