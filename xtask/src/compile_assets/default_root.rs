//! 世界ごとの板の世界の実行時形式の置き場と、その世界を既定の場所へ焼く入口。担当するのは「どの世界がどの出力ルートを占めるか」の
//! 対応だけであり、生成の手続きそのものは親モジュールが持つ。
//!
//! 世界ごとに出力ルートを分けるのは、1つの出力ルートが1つのカタログと1つのチャンク目録しか持てないためである。
//! 原点チャンクを占める世界どうしは同じ出力ルートへ同居できない。

use std::path::{Path, PathBuf};

use blitz_asset_compiler::{散布の焼き方, 遠景地形の焼き方};

use crate::asset_generator::{世界名, 生成器エラー};

use super::実行時形式を生成する;
use crate::verify::{検証の出力の置き場名, 検証の出力ルート};

const 既定ソースルート: &str = "assets";
pub const 板の世界の実行時形式の置き場: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("runtime_assets");
pub const 地形の世界の実行時形式の置き場: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("terrain_assets");
pub const 植生の世界の実行時形式の置き場: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("vegetation_assets");
pub const 見本の集落の世界の実行時形式の置き場: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("village_assets");
pub const 部品で組んだ木の並びの世界の実行時形式の置き場: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("part_tree_row_assets");
pub const 目視見本の世界の実行時形式の置き場: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("terrain_visual_assets");
pub const 場所巡りの世界の実行時形式の置き場: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("fox_tour_assets");
pub const 夜の多光源の世界の実行時形式の置き場: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("night_lights_assets");
pub const 屋内の多光源の世界の実行時形式の置き場: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("stone_hut_assets");

pub fn ソースルート() -> &'static Path {
    Path::new(既定ソースルート)
}

pub fn 既定を生成する() -> bool {
    実行時形式を生成する(
        ソースルート(),
        &検証の出力ルート::既定().名前が指す置き場(板の世界の実行時形式の置き場),
        世界名::板の世界,
    )
}

