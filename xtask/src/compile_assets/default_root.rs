/// 見本の集落も原点チャンクを占めるため、専用の板の世界の実行時形式の置き場へ焼く。
/// 引数なしの一括生成へ入れないのは、この世界の小物の原型が本体リポジトリの外にあるアセットリポジトリだけにあり、
/// それを持たない環境では焼けないためである。焼けない世界を一括生成へ入れると、アセットリポジトリを持たない環境で
/// 既存の検証が全部止まる。この世界を要るのは`village-draw`だけであり、そこが名指しで呼ぶ。
pub fn 見本の集落世界を既定で生成する() -> bool {
    実行時形式を生成する(
        ソースルート(),
        &検証の出力ルート::既定().名前が指す置き場(見本の集落の世界の実行時形式の置き場),
        世界名::見本の集落の世界,
    )
}

// 件数を変えた並びの対(家の並びと一間四方の骨格の並び)の出力ルートをここが持たないのは、規模ごとの出力ルートと
// 実行時アセットルートと実行時形式のパスが同じ綴りから決まり、それを1箇所で持つのが検収の入口の側だからである。
// 綴りが2つのファイルへ分かれると、`cargo xtask conform`のファイル名の重複の検査が拒む。
// 置き場は`xtask/src/part_row_draw/house_row.rs`と`xtask/src/part_row_draw/frame_row.rs`である。

/// 木の並びも原点チャンクを占めるため、専用の板の世界の実行時形式の置き場へ焼く。一括生成へ入れない理由は家の並びと同じであり、
/// 木の部品が本体リポジトリの外にあるアセットリポジトリだけにある。この世界を要るのは`part-tree-row-draw`だけである。
pub fn 部品で組んだ木の並びの出力ルート() -> PathBuf {
    検証の出力ルート::既定().名前が指す置き場(部品で組んだ木の並びの世界の実行時形式の置き場)
}

/// 既定のソースルートから名指しの出力ルートへ焼き、コンパイラの標準出力を返す。
/// 標準出力を返すのは、段4の検収が期待する発行数と個体数を、焼いた側が数えた報告の行から採るためである。
/// 一括生成へ入れないのは、家並みの部品が本体リポジトリの外にあるアセットリポジトリだけにあり、
/// それを持たない環境では焼けないためである。
pub fn 既定のソースから焼き標準出力を返す(出力ルート: &Path, 世界: 世界名) -> Result<String, 生成器エラー> {
    super::ルートを名指しして焼き標準出力を返す(ソースルート(), 出力ルート, 世界, 遠景地形の焼き方::焼かない, 散布の焼き方::焼く)
}

