//! 世界名: アセットコンパイラへ焼く対象として渡せる世界を数え上げた判別共用体。
//!
//! 平坦な定数の列挙で持っていたときは、どの綴りが「焼ける世界」なのかが型に無く、任意の`&str`が
//! 公開署名を8箇所流れていた。誤った綴りを渡しても型は通り、失敗するのはコンパイラを起動した後になる。
//! 枝で数え上げると、渡せる世界がこの一覧の中だけになり、足したときの対応漏れが`match`で見つかる。
//!
//! 枝の並びは`branch_order`が持つ。綴りへ戻すのはプロセス境界の1箇所だけである。綴りはアセットコンパイラ側
//! (`crates/blitz_asset_compiler/examples/compile_assets/world/argument_name.rs`)にも同じものがあり、
//! 食い違えば実行時アセット生成が「未知の世界名である」で失敗する。

mod branch_order;
#[cfg(test)]
mod round_trip_tests;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 世界名 {
    板の世界,
    地形の世界,
    植生の世界,
    見本の集落の世界,
    /// 間接照明の絵をオーナーが目で確かめるための世界。地面の上へ材質見本の立体と少数の小物を据える。
    /// 参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Ic-3bの実装」
    目視見本の世界,
    /// 頂点処理量の係数を同定する計測専用の世界の粗い側。地形の代表世界と同じ地面と配置を持つ。
    /// 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」
    頂点診断の粗い世界,
    /// 同じ計測専用の世界の細かい側。同居植生の原型の面を格子へ細分化したものを読む。
    頂点診断の細かい世界,
    /// ブロック圧縮の絵と誤差の統計を確かめるための世界。対照の素材(滑らかなグラデーションと決定的な雑音)を
    /// ベースカラーに持つ板2枚だけを原点チャンクへ置く。
    /// 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`「段割りと各段の完了条件」の段4
    ブロック圧縮の対照世界,
    /// 夜の多光源の検収世界。起伏のある地面1チャンクと、影の形で灯を見分けるための遮蔽物2件を持つ。
    /// 点光源はblitz_appの世界の宣言が置く。
    /// 参照: `_doc/設計/クラスタ多光源と点光源の影.md`「検収戦略(判断i)」
    夜の多光源の世界,
    /// 屋内の多光源の検収世界。平らな地面1チャンクの中央へ石積みの小屋を1棟据える。原型は外部のアセットリポジトリから来る。
    屋内の多光源の世界,
    /// クソゲー1本目「キツネの場所巡り」を遊ぶ世界。乱数の種から生成した9チャンクの地面へ目的地の目印を立て、
    /// 起動時に読むキツネのシーンと、実行中に高さを参照する高さ場を一緒に焼く。
    /// 参照: `_doc/設計/ゲーム制作アーキテクチャ.md`「第1段階の定義」
    場所巡りの世界,
}

impl 世界名 {
    /// プロセス境界でこの世界を指す綴り。生の綴りへ戻るのはここだけである。
    pub fn 綴り(self) -> &'static str {
        match self {
            Self::板の世界 => "chunk_world",
            Self::地形の世界 => "terrain_world",
            Self::植生の世界 => "vegetation_world",
            Self::見本の集落の世界 => "village_world",
            Self::目視見本の世界 => "terrain_visual_world",
            Self::頂点診断の粗い世界 => "vertex_diag_coarse_world",
            Self::頂点診断の細かい世界 => "vertex_diag_fine_world",
            Self::ブロック圧縮の対照世界 => "texture_compression_world",
            Self::夜の多光源の世界 => "night_lights_world",
            Self::屋内の多光源の世界 => "stone_hut_world",
            Self::場所巡りの世界 => "fox_tour_world",
        }
    }

    /// コマンドの引数として受け取った綴りを枝へ写す。知らない綴りは受け取らず、無いことを返す。
    /// 黙って既定の世界へ倒すと、綴りを打ち間違えた実行が別の世界を焼いたまま成功する。
    pub fn 引数の綴りから解釈する(綴り: &str) -> Option<Self> {
        Self::一覧().into_iter().find(|世界| 世界.綴り() == 綴り)
    }
}

impl std::fmt::Display for 世界名 {
    fn fmt(&self, 書き手: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(書き手, "{}", self.綴り())
    }
}
