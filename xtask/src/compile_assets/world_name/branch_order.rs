//! 焼ける世界の枝の並び。担当するのは、全枝を1度ずつ並べた一覧を作ることと、枝の追加を機械が
//! 要求する形を保つことだけであり、綴りそのものは親モジュールが持つ。
//!
//! 一覧を配列で手書きしないのは、手書きの一覧が枝の追加に追随しないためである。手書きだと、
//! 枝を足して`綴り()`だけを直した時にコンパイルも試験も通り、コマンド行からだけ新しい世界を
//! 解釈できない状態になる。`次の枝`が網羅の`match`であるため、枝を足すとそこでコンパイルが落ちる。

use super::世界名;

impl 世界名 {
    /// 焼ける世界の全枝。綴りの解釈と、使い方の案内が同じ一覧を読む。
    pub fn 一覧() -> Vec<Self> {
        let mut 一覧 = vec![Self::最初の枝];
        while let Some(次) = 一覧.last().and_then(|世界: &Self| 世界.次の枝()) {
            一覧.push(次);
        }
        一覧
    }

    /// 一覧の先頭。ここから`次の枝`を辿って全枝が並ぶ。
    const 最初の枝: Self = Self::板の世界;

    /// 一覧の並びでこの枝の次に来る枝。末尾だけが無しを返す。
    ///
    /// 注意: 枝を足したら、この`match`へ足すだけでなく、直前の枝の行を新しい枝へ向け直すこと。
    /// 向け直しを忘れると一覧から漏れる。漏れは`round_trip_tests`の綴りの重複と往復の検査が拾う。
    fn 次の枝(self) -> Option<Self> {
        match self {
            Self::板の世界 => Some(Self::地形の世界),
            Self::地形の世界 => Some(Self::植生の世界),
            Self::植生の世界 => Some(Self::見本の集落の世界),
            Self::見本の集落の世界 => Some(Self::目視見本の世界),
            Self::目視見本の世界 => Some(Self::頂点診断の粗い世界),
            Self::頂点診断の粗い世界 => Some(Self::頂点診断の細かい世界),
            Self::頂点診断の細かい世界 => Some(Self::ブロック圧縮の対照世界),
            Self::ブロック圧縮の対照世界 => Some(Self::夜の多光源の世界),
            Self::夜の多光源の世界 => Some(Self::屋内の多光源の世界),
            Self::屋内の多光源の世界 => Some(Self::場所巡りの世界),
            Self::場所巡りの世界 => None,
        }
    }
}
