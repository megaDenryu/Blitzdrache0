//! 世界名の枝と一覧が食い違っていないことの回帰検査。呼ばれるのは`cargo test`だけである。
//!
//! この検査を置くのは、`綴り()`が`match`で全枝を数えるのに対し、`一覧()`は配列であり、
//! 枝を足したときに配列側の書き漏らしをコンパイラが止められないためである。書き漏らすと、
//! コマンド行の綴りの解釈だけが新しい世界を知らないまま「知らない世界名である」を返す。

#![allow(clippy::unwrap_used)]

use super::世界名;

/// 一覧の件数が枝の数と一致すること。枝を足して一覧を直し忘れると、この数が合わなくなる。
/// 枝の数はこの検査だけが写しで持つため、枝を足すときはここも直す。
const 枝の数: usize = 11;

#[test]
fn 一覧が全ての枝を1度ずつ持つ() {
    let 一覧 = 世界名::一覧();
    assert_eq!(一覧.len(), 枝の数, "一覧の件数が枝の数と違う");
    let mut 綴り一覧: Vec<&str> = 一覧.iter().map(|世界| 世界.綴り()).collect();
    綴り一覧.sort_unstable();
    let 重複前の件数 = 綴り一覧.len();
    綴り一覧.dedup();
    assert_eq!(綴り一覧.len(), 重複前の件数, "一覧の中に同じ綴りの世界が2つある");
}

#[test]
fn 綴りから解釈すると元の枝へ戻る() {
    for 世界 in 世界名::一覧() {
        let 戻り = 世界名::引数の綴りから解釈する(世界.綴り());
        assert_eq!(戻り, Some(世界), "{}の綴りが元の枝へ戻らない", 世界.綴り());
    }
}

#[test]
fn 知らない綴りは無しになる() {
    assert_eq!(世界名::引数の綴りから解釈する("unknown_world"), None);
    assert_eq!(世界名::引数の綴りから解釈する(""), None);
}
