//! 世界名の枝と一覧が食い違っていないことの回帰検査。呼ばれるのは`cargo test`だけである。
//!
//! 枝の追加そのものは`次の枝`の網羅`match`がコンパイル時に要求する。ここが拾うのは、その`match`へ
//! 足したうえで直前の枝からの向け直しを忘れ、新しい枝が連なりから漏れる形である。
//! 漏れると、コマンド行の綴りの解釈だけが新しい世界を知らないまま「知らない世界名である」を返す。

#![allow(clippy::unwrap_used)]

use super::世界名;

#[test]
fn 一覧が同じ枝を2度持たない() {
    let 一覧 = 世界名::一覧();
    let mut 綴り一覧: Vec<&str> = 一覧.iter().map(|世界| 世界.綴り()).collect();
    綴り一覧.sort_unstable();
    let 重複前の件数 = 綴り一覧.len();
    綴り一覧.dedup();
    assert_eq!(
        綴り一覧.len(),
        重複前の件数,
        "一覧の中に同じ綴りの世界が2つある(枝の連なりが輪になっている)"
    );
}

/// 枝を足して`次の枝`へは書いたが、直前の枝からの向け直しを忘れた形を拾う。
/// 一覧のどの枝から辿っても末尾へ到達し、途中の枝が一覧に必ず現れることを確かめる。
#[test]
fn 全ての枝が一覧から辿れる() {
    let 一覧 = 世界名::一覧();
    for 世界 in &一覧 {
        assert!(
            世界名::引数の綴りから解釈する(世界.綴り()).is_some(),
            "{}が一覧に在るのに綴りから解釈できない",
            世界.綴り()
        );
    }
    assert!(一覧.len() >= 2, "一覧が枝を1つしか持たない");
}

#[test]
fn 綴りから解釈すると元の枝へ戻る() {
    for 世界 in 世界名::一覧() {
        let 戻り = 世界名::引数の綴りから解釈する(世界.綴り());
        assert_eq!(戻り, Some(世界), "{}の綴りが元の枝へ戻らない", 世界.綴り());
    }
}

#[test]
fn 知らない綴りは無しになる() {
    assert_eq!(世界名::引数の綴りから解釈する("unknown_world"), None);
    assert_eq!(世界名::引数の綴りから解釈する(""), None);
}
