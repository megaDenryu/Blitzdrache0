//! 空ありと空なしの2枚から、空が塗った範囲と空の勾配を判定する工程。
//! 受け取るのは同じ条件で空パスだけが違う2枚、返すのは判定に使った実測値である。
//!
//! 空なしの画像でクリア色のままの画素を空の領域、それ以外をジオメトリの領域と見なす。
//! クリア色は左上の画素から取る。カメラを地平線より上へ向けた構図では、画面左上に地面が来ることはない。
//! 距離区分ごとの色の測り方は`gradient`にある。

use super::gradient;
use super::run::実行結果;

/// 天頂と地平で求める青みの差の下限。これを下回るときは勾配が無いか、勾配の向きが逆である。
const 青み差の下限: i32 = 10;

pub(super) struct 判定結果 {
    pub(super) 空画素数: u64,
    pub(super) 塗られた空画素数: u64,
    pub(super) 幾何画素数: u64,
    pub(super) 青み差: i32,
}

pub(super) fn 画素を判定する(空あり: &実行結果, 空なし: &実行結果) -> Result<判定結果, String> {
    寸法の一致を確かめる(空あり, 空なし)?;
    let クリア色 = 空なし.画素(0, 0);
    let 計数 = 数える(空あり, 空なし, クリア色);
    if 計数.幾何画素数 == 0 {
        return Err("空なしの画像にジオメトリの画素が1つも無い(地形が描かれていない)".to_string());
    }
    if 計数.一致しない幾何画素数 != 0 {
        return Err(format!(
            "空を入れるとジオメトリの画素が{}個変わった(空がクリア深度以外へ描かれている)",
            計数.一致しない幾何画素数
        ));
    }
    if 計数.塗られた空画素数 != 計数.空画素数 {
        return Err(format!(
            "空の領域{}画素のうち{}画素しか塗られていない",
            計数.空画素数, 計数.塗られた空画素数
        ));
    }
    let 青み = gradient::距離区分別の青みを求める(空あり, 空なし, クリア色)?;
    let 青み差 = 青み.天頂 - 青み.地平;
    if 青み差 < 青み差の下限 {
        return Err(format!(
            "天頂の青み{}と地平の青み{}の差が{青み差}で、下限{青み差の下限}に満たない",
            青み.天頂, 青み.地平
        ));
    }
    Ok(判定結果 {
        空画素数: 計数.空画素数,
        塗られた空画素数: 計数.塗られた空画素数,
        幾何画素数: 計数.幾何画素数,
        青み差,
    })
}

struct 画素計数 {
    空画素数: u64,
    塗られた空画素数: u64,
    幾何画素数: u64,
    一致しない幾何画素数: u64,
}

fn 数える(空あり: &実行結果, 空なし: &実行結果, クリア色: [u8; 3]) -> 画素計数 {
    let mut 計数 = 画素計数 {
        空画素数: 0,
        塗られた空画素数: 0,
        幾何画素数: 0,
        一致しない幾何画素数: 0,
    };
    for y in 0..空なし.高さ {
        for x in 0..空なし.幅 {
            let (無, 有) = (空なし.画素(x, y), 空あり.画素(x, y));
            if 無 == クリア色 {
                計数.空画素数 += 1;
                計数.塗られた空画素数 += u64::from(有 != クリア色);
            } else {
                計数.幾何画素数 += 1;
                計数.一致しない幾何画素数 += u64::from(有 != 無);
            }
        }
    }
    計数
}

fn 寸法の一致を確かめる(空あり: &実行結果, 空なし: &実行結果) -> Result<(), String> {
    if 空あり.幅 != 空なし.幅 || 空あり.高さ != 空なし.高さ {
        return Err(format!("2条件の寸法が違う: {}x{}と{}x{}", 空あり.幅, 空あり.高さ, 空なし.幅, 空なし.高さ));
    }
    Ok(())
}
