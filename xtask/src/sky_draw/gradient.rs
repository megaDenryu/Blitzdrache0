//! 空の勾配を測る工程。受け取るのは2枚の画像とクリア色、返すのは天頂側の帯と地平側の帯の青みである。
//! 青みは青成分から赤成分を引いた値であり、解析近似は天頂を青く地平を白く出すため、この差が勾配の有無を表す。

use crate::acceptance::{判定の名前, 判定の破れ, 画素の横位置, 画素の縦位置, 読み戻し画像};

/// 天頂側の帯と地平側の帯。どちらも上半分に取り、地面が入らない範囲に収める。
const 天頂帯の下端割合: usize = 12;
const 地平帯の上端割合: usize = 4;
const 地平帯の下端割合: usize = 3;
/// 帯ごとに求める最小の空画素数。構図が変わって帯が地面で埋まったときに、少数の画素で平均を語らないための下限である。
const 帯の最小画素数: u64 = 1_000;

pub(super) struct 帯別の青み {
    pub(super) 天頂: i32,
    pub(super) 地平: i32,
}

pub(super) fn 帯別の青みを求める(
    空あり: &読み戻し画像,
    空なし: &読み戻し画像,
    クリア色: [u8; 3],
) -> Result<帯別の青み, 判定の破れ> {
    let 高さ = 空あり.高さ().画素数();
    Ok(帯別の青み {
        天頂: 帯の青みを求める(空あり, 空なし, クリア色, 0, 高さ / 天頂帯の下端割合)?,
        地平: 帯の青みを求める(空あり, 空なし, クリア色, 高さ / 地平帯の上端割合, 高さ / 地平帯の下端割合)?,
    })
}

/// 帯の中の空画素だけを平均した青み。空画素かどうかは空なしの画像がクリア色のままかで決める。
fn 帯の青みを求める(
    空あり: &読み戻し画像,
    空なし: &読み戻し画像,
    クリア色: [u8; 3],
    y開始: usize,
    y終端: usize,
) -> Result<i32, 判定の破れ> {
    let (mut 合計, mut 件数) = (0i64, 0u64);
    for y in y開始..y終端 {
        for x in 0..空なし.幅().画素数() {
            if 空なし.座標の画素(画素の横位置::生成する(x), 画素の縦位置::生成する(y)) != クリア色 {
                continue;
            }
            let 色 = 空あり.座標の画素(画素の横位置::生成する(x), 画素の縦位置::生成する(y));
            合計 += i64::from(色[2]) - i64::from(色[0]);
            件数 += 1;
        }
    }
    帯の空画素の判定名(y開始, y終端).下限を課す(件数, 帯の最小画素数)?;
    Ok(平均を求める(合計, 件数))
}

fn 帯の空画素の判定名(y開始: usize, y終端: usize) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("行{y開始}から{y終端}の帯の中の空画素の件数"))
}

/// 帯の中の青みの平均。整数の割り算で求めるのは、青みが階調の整数であり、平均も同じ階調の目盛りで読むためである。
///
/// 注意: 件数がi64へ、平均がi32へ収まらないことは起こらない。件数は絵の画素数を超えず、
/// 1画素の青みは-255から255に収まるためその平均も同じ範囲に収まる。収まらない値で止めるのは、
/// 起こりえない変換の失敗を判定の失敗として運ばないためである。
fn 平均を求める(合計: i64, 件数: u64) -> i32 {
    let 平均 = 合計 / i64::try_from(件数).unwrap_or(i64::MAX);
    i32::try_from(平均).unwrap_or(i32::MAX)
}
