//! 空の勾配を測る工程。受け取るのは2枚の画像とクリア色、返すのは天頂側の帯と地平側の帯の青みである。
//! 青みは青成分から赤成分を引いた値であり、解析近似は天頂を青く地平を白く出すため、この差が勾配の有無を表す。

use super::run::実行結果;

/// 天頂側の帯と地平側の帯。どちらも上半分に取り、地面が入らない範囲に収める。
const 天頂帯の下端割合: usize = 12;
const 地平帯の上端割合: usize = 4;
const 地平帯の下端割合: usize = 3;
/// 距離区分ごとに求める最小の空画素数。構図が変わって距離区分が地面で埋まったときに、少数の画素で平均を語らないための下限である。
const 距離区分の最小画素数: u64 = 1_000;

pub(super) struct 距離区分別の青み {
    pub(super) 天頂: i32,
    pub(super) 地平: i32,
}

pub(super) fn 距離区分別の青みを求める(
    空あり: &実行結果,
    空なし: &実行結果,
    クリア色: [u8; 3],
) -> Result<距離区分別の青み, String> {
    let 高さ = 空あり.高さ;
    Ok(距離区分別の青み {
        天頂: 距離区分の青みを求める(空あり, 空なし, クリア色, 0, 高さ / 天頂帯の下端割合)?,
        地平: 距離区分の青みを求める(空あり, 空なし, クリア色, 高さ / 地平帯の上端割合, 高さ / 地平帯の下端割合)?,
    })
}

/// 距離区分の中の空画素だけを平均した青み。空画素かどうかは空なしの画像がクリア色のままかで決める。
fn 距離区分の青みを求める(
    空あり: &実行結果, 空なし: &実行結果, クリア色: [u8; 3], y開始: usize, y終端: usize
) -> Result<i32, String> {
    let (mut 合計, mut 件数) = (0i64, 0u64);
    for y in y開始..y終端 {
        for x in 0..空なし.幅 {
            if 空なし.画素(x, y) != クリア色 {
                continue;
            }
            let 色 = 空あり.画素(x, y);
            合計 += i64::from(色[2]) - i64::from(色[0]);
            件数 += 1;
        }
    }
    if 件数 < 距離区分の最小画素数 {
        return Err(format!("行{y開始}から{y終端}の距離区分に空画素が{件数}個しかない"));
    }
    let 平均 = 合計 / i64::try_from(件数).map_err(|誤り| format!("画素数がi64に収まらない: {誤り}"))?;
    i32::try_from(平均).map_err(|誤り| format!("青みの平均がi32に収まらない: {誤り}"))
}
