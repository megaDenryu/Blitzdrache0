//! アプリの`--report-streaming-summary`が出す人間向け要約から、検収が使う整数だけを読む工程。
//! 受け取るのは終了時報告、返すのは転送量・使用量・台帳登録数・LOD変更の数である。
//! 行の綴りは`crates/blitz_app/src/reports/streaming_summary.rs`の出力と一致させている。
//! ストリーミングを通す検収が2つ以上あるため、同じ行を2箇所で読まないようここへ集める。
//!
//! 行の見出しと鍵を型で持つのは、読む側が綴りをその場で書くと、出す側の書式が変わったときに
//! 直し漏れた読み取りだけが静かに別の値を採るためである。読み取りの手順は検収の器の`終了時報告`が持つ。

#[cfg(test)]
mod reading_tests;

use crate::acceptance::{報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

const 読込の見出し: 報告の見出し = 報告の見出し::定数から生成する("ディスク読込:");
const 解除の見出し: 報告の見出し = 報告の見出し::定数から生成する("GPU資源解除:");
const 最大使用量の見出し: 報告の見出し = 報告の見出し::定数から生成する("最大使用量:");
const 最大台帳登録数の見出し: 報告の見出し = 報告の見出し::定数から生成する("最大台帳登録数:");
const 最終台帳登録数の見出し: 報告の見出し = 報告の見出し::定数から生成する("最終台帳登録数:");
const 詳細段の変更フレーム数の見出し: 報告の見出し = 報告の見出し::定数から生成する("LOD変更フレーム数:");
const 詳細段の変更時の読込開始の見出し: 報告の見出し = 報告の見出し::定数から生成する("LOD変更時の読込開始:");
const 最終フレームの地形詳細段の見出し: 報告の見出し = 報告の見出し::定数から生成する("最終フレームの地形詳細段:");

const バイト数の手前の区切り: 報告の行の鍵 = 報告の行の鍵::定数から生成する("/"); // 「25件 / 11155300 bytes」の形の行で、バイト数の手前に立つ
const 最大RAM使用量の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("RAM");
const 最大VRAM使用量の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("VRAM");

/// 段ごとの束数を「段0=3件 段1=2件」と並べる行で、段1つを数える語。
const 段1つを数える語: &str = "件";

/// 1回の実行のストリーミング要約から読んだ整数。`最終台帳登録数`は、`最大台帳登録数`が実行の途中の値であるのに
/// 対して終状態を表すため、解除を経た実行に不要な束が残っているかどうかを一度も解除していない実行と
/// 突き合わせられる。`最終段種類数`は段の分布の行に現れた「件」の数で数える。
pub struct ストリーミング要約報告 {
    pub ディスク読込件数: u64,
    pub ディスク読込バイト数: u64,
    pub gpu解除件数: u64,
    pub 最大ramバイト数: u64,
    pub 最大vramバイト数: u64,
    pub 最大台帳登録数: u64,
    pub 最終台帳登録数: u64, // 最終フレームの台帳登録数
    pub lod変更フレーム数: u64,
    pub lod変更時読込開始件数: u64,
    pub 最終段種類数: usize, // 最終フレームに立っていた地形詳細段の種類数
}

pub fn 取り出す(報告: &終了時報告) -> Result<ストリーミング要約報告, 検収エラー> {
    let 読込行 = 報告.見出しの1行(&読込の見出し)?;
    let 最大使用量行 = 報告.見出しの1行(&最大使用量の見出し)?;
    Ok(ストリーミング要約報告 {
        ディスク読込件数: 見出しに続く件数(&読込行, &読込の見出し)?,
        ディスク読込バイト数: 読込行.鍵に結ばれた数(&バイト数の手前の区切り, 鍵に値が結ばれる形::次の語が値である)?,
        gpu解除件数: 見出しの行の件数(報告, &解除の見出し)?,
        最大ramバイト数: 最大使用量行.鍵に結ばれた数(&最大RAM使用量の鍵, 鍵に値が結ばれる形::次の語が値である)?,
        最大vramバイト数: 最大使用量行.鍵に結ばれた数(&最大VRAM使用量の鍵, 鍵に値が結ばれる形::次の語が値である)?,
        最大台帳登録数: 報告.見出しに続く数(&最大台帳登録数の見出し)?,
        最終台帳登録数: 報告.見出しに続く数(&最終台帳登録数の見出し)?,
        lod変更フレーム数: 報告.見出しに続く数(&詳細段の変更フレーム数の見出し)?,
        lod変更時読込開始件数: 見出しの行の件数(報告, &詳細段の変更時の読込開始の見出し)?,
        最終段種類数: 報告.見出しに続く本文(&最終フレームの地形詳細段の見出し)?.matches(段1つを数える語).count(),
    })
}

/// 「見出し: 25件」の形で件数だけが続く行を読む。単位の接尾辞を落としてから数として読む。
fn 見出しの行の件数(報告: &終了時報告, 見出し: &報告の見出し) -> Result<u64, 検収エラー> {
    見出しに続く件数(&報告.見出しの1行(見出し)?, 見出し)
}

fn 見出しに続く件数(行: &報告の行, 見出し: &報告の見出し) -> Result<u64, 検収エラー> {
    let 鍵 = 報告の行の鍵::組み立てた綴りから生成する(見出し.to_string());
    行.鍵に結ばれた語から数字だけを読む(&鍵, 鍵に値が結ばれる形::次の語が値である)
}
