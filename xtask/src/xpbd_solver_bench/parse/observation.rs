//! 方式の観測の6行(題材・検証・再現性・収束・CPU参照との差・資源)を読む工程。受け取るのは終了時報告、返すのは方式の観測である。
//! 行はどれも「見出し 鍵=値 鍵=値 …」の形であり、鍵は等号の後ろに値を持つ。

use super::super::record::方式の観測;
use crate::acceptance::{報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

const 題材の見出し: 報告の見出し = 報告の見出し::定数から生成する("XPBD並列方式計測");
const 検証の見出し: 報告の見出し = 報告の見出し::定数から生成する("XPBD検証");
const 再現性の見出し: 報告の見出し = 報告の見出し::定数から生成する("XPBD再現性");
const 収束の見出し: 報告の見出し = 報告の見出し::定数から生成する("XPBD収束");
const 参照との差の見出し: 報告の見出し = 報告の見出し::定数から生成する("XPBDのCPU参照との差");
const 資源の見出し: 報告の見出し = 報告の見出し::定数から生成する("XPBD資源");

pub(super) fn 方式の観測を読む(報告: &終了時報告) -> Result<方式の観測, 検収エラー> {
    let 題材 = 報告.見出しの1行(&題材の見出し)?;
    let 検証 = 報告.見出しの1行(&検証の見出し)?;
    let 再現性 = 報告.見出しの1行(&再現性の見出し)?;
    let 収束 = 報告.見出しの1行(&収束の見出し)?;
    let 差 = 報告.見出しの1行(&参照との差の見出し)?;
    let 資源 = 報告.見出しの1行(&資源の見出し)?;
    Ok(方式の観測 {
        点の数: 数(&題材, "点の数")?,
        拘束の数: 数(&題材, "拘束の数")?,
        色の数: 数(&題材, "色の数")?,
        グラフ生成ミリ秒: 数(&題材, "グラフ生成ミリ秒")?,
        前計算ミリ秒: 数(&題材, "前計算ミリ秒")?,
        検証層の状況: 綴り(&検証, "状況")?,
        検証件数: 数(&検証, "件数")?,
        位置が再現するか: 綴り(&再現性, "位置")? == "一致",
        乗数が再現するか: 綴り(&再現性, "乗数")? == "一致",
        位置の指紋: 綴り(&再現性, "位置の指紋")?,
        gpuの拘束違反: 数(&収束, "GPUの拘束違反の二乗平均平方根")?,
        cpuの拘束違反: 数(&収束, "CPUの拘束違反の二乗平均平方根")?,
        全て有限か: 綴り(&収束, "全て有限")? == "はい",
        比較の刻み数: 数(&差, "比較の刻み数")?,
        位置の最大差: 数(&差, "位置の最大差")?,
        位置の平均差: 数(&差, "位置の平均差")?,
        乗数の最大差: 数(&差, "乗数の最大差")?,
        乗数の平均差: 数(&差, "乗数の平均差")?,
        バッファ合計バイト数: 数(&資源, "バッファ合計バイト数")?,
        一刻みのディスパッチ数: 数(&資源, "一刻みのディスパッチ数")?,
        原子演算を使うか: 綴り(&資源, "原子演算")? == "あり",
    })
}

fn 数<数: std::str::FromStr>(行: &報告の行, 鍵: &str) -> Result<数, 検収エラー> {
    行.鍵に結ばれた数(
        &報告の行の鍵::組み立てた綴りから生成する(鍵.to_string()),
        鍵に値が結ばれる形::等号の後ろが値である,
    )
}

fn 綴り(行: &報告の行, 鍵: &str) -> Result<String, 検収エラー> {
    行.鍵に結ばれた綴り(
        &報告の行の鍵::組み立てた綴りから生成する(鍵.to_string()),
        鍵に値が結ばれる形::等号の後ろが値である,
    )
}
