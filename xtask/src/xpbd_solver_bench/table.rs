//! 採れた値を表として並べる工程。受け取るのは標本の並び、返すものは無く、標準出力へ書く。
//! 1行が1実行であり、一刻みの合計の分位と、収束・CPU参照との差・再現性・資源を横に並べる。工程の内訳は`window.tsv`が持つ。

use super::record::一標本;

pub(super) fn 表示する(標本一覧: &[一標本]) {
    println!("XPBDの並列方式の計測(1実行の窓の集約、GPU時間の単位ミリ秒):");
    println!(
        "実行\t周回\t順序位置\t条件\t合計平均\t合計p50\t合計p95\t標本数\tGPUの拘束違反\tCPUの拘束違反\t位置の最大差\t乗数の最大差\t位置の再現\t乗数の再現\tバッファ合計バイト数\t一刻みのディスパッチ数\t色の数\t原子演算\t前計算ミリ秒"
    );
    for 標本 in 標本一覧 {
        let 分布 = 標本.合計の分布();
        let 観測 = &標本.観測;
        println!(
            "{}\t{}\t{}\t{}\t{:.4}\t{:.4}\t{:.4}\t{}\t{:.3e}\t{:.3e}\t{:.3e}\t{:.3e}\t{}\t{}\t{}\t{}\t{}\t{}\t{:.3}",
            標本.実行番号,
            標本.周回番号,
            標本.順序位置,
            標本.条件名(),
            分布.平均ミリ秒,
            分布.p50ミリ秒,
            分布.p95ミリ秒,
            分布.標本数,
            観測.gpuの拘束違反,
            観測.cpuの拘束違反,
            観測.位置の最大差,
            観測.乗数の最大差,
            再現の語(観測.位置が再現するか),
            再現の語(観測.乗数が再現するか),
            観測.バッファ合計バイト数,
            観測.一刻みのディスパッチ数,
            観測.色の数,
            if 観測.原子演算を使うか { "あり" } else { "なし" },
            観測.前計算ミリ秒
        );
    }
}

fn 再現の語(再現するか: bool) -> &'static str {
    if 再現するか { "一致" } else { "不一致" }
}
