//! 採れた値のファイルへの書き出し。受け取るのは書き先と標本の並び、返すものは無い。
//! どちらのファイルも先頭に構築の由来の注記を置く(井桁で始まる行は表を読む道具が注記として飛ばす)。

use std::path::Path;

use super::super::error::XPBDの並列方式の計測エラー;
use super::super::intervals;
use super::一標本;
use crate::release_build::{tsvの前置き, 構築の由来};

pub(in super::super) fn 生値を書く(
    書き先: &Path, 標本一覧: &[一標本], 由来: &構築の由来
) -> Result<(), XPBDの並列方式の計測エラー> {
    let mut 本文 = tsvの前置き(&由来.注記一覧());
    本文.push_str("実行番号\t周回\t順序位置\t条件\t読み取り順\t区間\t経過ミリ秒\n");
    for 標本 in 標本一覧 {
        for 生値 in &標本.フレーム別の値一覧 {
            本文.push_str(&format!(
                "{}\t{}\t{}\t{}\t{}\t{}\t{:.4}\n",
                標本.実行番号,
                標本.周回番号,
                標本.順序位置,
                標本.条件名(),
                生値.読み取り順,
                生値.区間名,
                生値.経過ミリ秒
            ));
        }
    }
    書く(書き先, &本文)
}

/// 窓の集約と方式ごとの量を1実行1組で書く。区間の行の後ろに、その実行の観測を1行で置く。
pub(in super::super) fn 窓の集約を書く(
    書き先: &Path,
    標本一覧: &[一標本],
    由来: &構築の由来,
) -> Result<(), XPBDの並列方式の計測エラー> {
    let mut 本文 = tsvの前置き(&由来.注記一覧());
    本文.push_str("実行番号\t周回\t順序位置\t条件\t区間\t平均ミリ秒\tp50ミリ秒\tp95ミリ秒\t標本数\n");
    for 標本 in 標本一覧 {
        for (区間名, 分布) in intervals::全区間一覧(標本.条件.方式).iter().zip(&標本.区間別) {
            本文.push_str(&format!(
                "{}\t{}\t{}\t{}\t{区間名}\t{:.4}\t{:.4}\t{:.4}\t{}\n",
                標本.実行番号,
                標本.周回番号,
                標本.順序位置,
                標本.条件名(),
                分布.平均ミリ秒,
                分布.p50ミリ秒,
                分布.p95ミリ秒,
                分布.標本数
            ));
        }
    }
    本文.push_str("実行番号\t条件\t点の数\t拘束の数\t色の数\tグラフ生成ミリ秒\t前計算ミリ秒\t位置の再現\t乗数の再現\tGPUの拘束違反\tCPUの拘束違反\t比較の刻み数\t位置の最大差\t乗数の最大差\tバッファ合計バイト数\t一刻みのディスパッチ数\t原子演算\t位置の指紋\n");
    for 標本 in 標本一覧 {
        let 観測 = &標本.観測;
        本文.push_str(&format!(
            "{}\t{}\t{}\t{}\t{}\t{:.3}\t{:.3}\t{}\t{}\t{:.6e}\t{:.6e}\t{}\t{:.6e}\t{:.6e}\t{}\t{}\t{}\t{}\n",
            標本.実行番号,
            標本.条件名(),
            観測.点の数,
            観測.拘束の数,
            観測.色の数,
            観測.グラフ生成ミリ秒,
            観測.前計算ミリ秒,
            観測.位置が再現するか,
            観測.乗数が再現するか,
            観測.gpuの拘束違反,
            観測.cpuの拘束違反,
            観測.比較の刻み数,
            観測.位置の最大差,
            観測.乗数の最大差,
            観測.バッファ合計バイト数,
            観測.一刻みのディスパッチ数,
            観測.原子演算を使うか,
            観測.位置の指紋
        ));
    }
    書く(書き先, &本文)
}

fn 書く(書き先: &Path, 本文: &str) -> Result<(), XPBDの並列方式の計測エラー> {
    std::fs::write(書き先, 本文).map_err(|誤り| XPBDの並列方式の計測エラー::計測の結果を書けなかった {
        パス: 書き先.to_path_buf(),
        誤り,
    })
}
