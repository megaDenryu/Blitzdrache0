//! 機械判定。採用の合否は判定しない(採用規則は実測を読んで人が設計正本へ書く)。持つのは5つである。
//! validationの指摘が0件であること、測れた値がすべて有限であること、報告した分位が生標本から再現されること、
//! 決定的であるべき方式の2回の実行がビット一致すること、短い実行でのCPUの参照計算との差が許容に収まることである。
//!
//! 許容差の根拠: 位置は2メートル以下であり単精度の刻みは2.4e-7メートル、比較の刻み数10×反復4回=40回の射影で
//! 演算順の違いが積み重なった実測の最大は1e-5メートルの桁(不規則グラフの彩色で9.6e-6)であり、その10倍を許容にする。
//! 原子加算は補正を2の-20乗メートルへ量子化するため、接続数12×半量子4.8e-7×40回=2.3e-4メートルが最悪の上界であり、
//! 実測の最大4.0e-5の10倍でその上界も覆う5e-4メートルを許容にする。乗数は1e-5キログラム・メートルの桁の量であり、
//! 実測の最大差4.8e-8の20倍の1e-6を許容にする。

use super::intervals;
use super::record::一標本;
use super::schedule::方式;
use crate::acceptance::{判定の名前, 判定の破れ};
use crate::depth_prepass_cost::quantile_check::順位の値;

const 位置の許容メートル: f64 = 1.0e-4;
const 原子加算の位置の許容メートル: f64 = 5.0e-4;
const 乗数の許容: f64 = 1.0e-6;
/// 4桁で書かれた値どうしの比較であるため、食い違いは丸めの誤差でなく計算の誤りである。
const 分位の再現の許容: f64 = 1.0e-9;

pub(super) fn 検証層の指摘が零件であることを確かめる(標本一覧: &[一標本]) -> Result<(), 判定の破れ> {
    for 標本 in 標本一覧 {
        判定名(標本, "validation層の状況").綴りの一致を課す(&標本.観測.検証層の状況, "有効")?;
        判定名(標本, "validationの指摘件数").零件であることを課す(標本.観測.検証件数)?;
    }
    Ok(())
}

pub(super) fn 値が有限であることを確かめる(標本一覧: &[一標本]) -> Result<(), 判定の破れ> {
    for 標本 in 標本一覧 {
        判定名(標本, "読み戻した位置と乗数の有限性").真であることを課す(標本.観測.全て有限か)?;
        for (区間名, 分布) in intervals::全区間一覧(標本.条件.方式).iter().zip(&標本.区間別) {
            for (量の名前, 値) in [("平均", 分布.平均ミリ秒), ("p50", 分布.p50ミリ秒), ("p95", 分布.p95ミリ秒)] {
                判定名(標本, &format!("区間{区間名}の{量の名前}")).有限であることを課す(値)?;
            }
        }
        for (名前, 値) in [("GPUの拘束違反", 標本.観測.gpuの拘束違反), ("CPUの拘束違反", 標本.観測.cpuの拘束違反)] {
            判定名(標本, 名前).有限であることを課す(値)?;
        }
    }
    Ok(())
}

/// 分位の求め方をこちらでもう一度当てるのは意図した重複である(`depth_prepass_cost::quantile_check`と同じ根拠)。
pub(super) fn 報告の分位が生標本から再現されることを確かめる(標本一覧: &[一標本]) -> Result<(), 判定の破れ> {
    for 標本 in 標本一覧 {
        let 分布 = 標本.合計の分布();
        let mut 窓: Vec<f64> = 標本
            .フレーム別の値一覧
            .iter()
            .filter(|生値| 生値.区間名 == intervals::一刻みの合計)
            .map(|生値| 生値.経過ミリ秒)
            .rev()
            .take(標本.窓の標本数)
            .collect();
        判定名(標本, "生標本から採れた窓の件数").一致を課す(窓.len(), 分布.標本数を数へ())?;
        窓.sort_by(f64::total_cmp);
        for (名前, 計算し直した値, 報告値) in [("p50", 順位の値(&窓, 50), 分布.p50ミリ秒), ("p95", 順位の値(&窓, 95), 分布.p95ミリ秒)]
        {
            let 隔たり: f64 = (計算し直した値 - 報告値).abs();
            判定名(
                標本,
                &format!("生標本から計算し直した{名前}{計算し直した値:.4}と報告値{報告値:.4}の隔たり"),
            )
            .上限を課す(隔たり, 分位の再現の許容)?;
        }
    }
    Ok(())
}

pub(super) fn 決定的な方式が再現することを確かめる(標本一覧: &[一標本]) -> Result<(), 判定の破れ> {
    for 標本 in 標本一覧.iter().filter(|標本| 標本.条件.方式.決定的であるべきか()) {
        判定名(標本, "2回の実行の位置のビット一致").真であることを課す(標本.観測.位置が再現するか)?;
        判定名(標本, "2回の実行の乗数のビット一致").真であることを課す(標本.観測.乗数が再現するか)?;
    }
    Ok(())
}

pub(super) fn 参照計算との差が許容に収まることを確かめる(標本一覧: &[一標本]) -> Result<(), 判定の破れ> {
    for 標本 in 標本一覧 {
        let 位置の許容 = match 標本.条件.方式 {
            方式::原子加算 => 原子加算の位置の許容メートル,
            方式::グラフ彩色 | 方式::二段階 => 位置の許容メートル,
        };
        判定名(標本, "短い実行でのCPU参照との位置の最大差").上限を課す(標本.観測.位置の最大差, 位置の許容)?;
        判定名(標本, "短い実行でのCPU参照との乗数の最大差").上限を課す(標本.観測.乗数の最大差, 乗数の許容)?;
    }
    Ok(())
}

fn 判定名(標本: &一標本, 名前: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("実行{}({})の{名前}", 標本.実行番号, 標本.条件名()))
}
