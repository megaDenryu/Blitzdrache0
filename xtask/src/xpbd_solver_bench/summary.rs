//! 計測の1行要約の組み立て。受け取るのは標本の並びと出力先と指定と構築の由来、返すのは人が読む1行である。
//! 判定も表示も持たないのは、この工程が「実測をどう言葉にするか」だけを担うためである。

use std::path::Path;

use super::plan::実行の指定;
use super::record::一標本;
use super::schedule;

pub(super) fn 要約を組む(
    標本一覧: &[一標本], 出力先: &Path, 指定: &実行の指定, 由来: &crate::release_build::構築の由来
) -> String {
    let 再現した数 = 標本一覧
        .iter()
        .filter(|標本| 標本.観測.位置が再現するか && 標本.観測.乗数が再現するか)
        .count();
    format!(
        "1実行{}刻み(反復{}回・点{}個)の{}方式×{}グラフを回転順で{}周し、{}実行すべてがvalidation0件・有限・分位の再現・CPU参照との許容内の差を満たした。2回の実行のビット一致は{}実行中{}実行。区間別の表とフレーム別の生値は{}にある。計測に使ったバイナリの由来は{}",
        指定.刻み数,
        指定.反復回数,
        指定.点の数,
        指定.方式一覧.len(),
        指定.グラフ一覧.len(),
        schedule::周回数,
        標本一覧.len(),
        標本一覧.len(),
        再現した数,
        出力先.display(),
        由来.一行にする()
    )
}
