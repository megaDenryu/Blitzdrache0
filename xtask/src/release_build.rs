//! 計測用のリリースビルドの唯一の入口。実行ファイルを直接起動する計測コマンドは、条件を1つも走らせる前に
//! ここを1度だけ通る。担当するのは、構築を済ませることと、構築したバイナリの由来を答えることである。
//!
//! 工程を1つに集めるのは、構築と由来の記録を対で持たせるためである。分かれていると、構築だけを済ませて
//! 由来を残さない入口が成立し、その入口の成果物だけが「どの基準から作ったバイナリで測ったか」を答えられなくなる。
//! **閉じている欠陥は誤帰属である**。ある実装状態で正しく採った値が、成果物に版を持たないために、後から
//! 別の実装状態の値として読まれた(2026-08-05の深度プリパスの計測で実際に起きた)。
//!
//! 構築の標準出力と所要時間は計測窓へ入らない。ここが戻ってから初めて条件列が始まるためである。

mod provenance;

use std::path::Path;
use std::process::Command;

pub use provenance::構築の由来;

/// 計測が直に叩く実行ファイル。構築の対象と、由来を採る対象が同じ1つであることをこの定数が保つ。
pub const 計測用の実行ファイル: &str = "target/release/blitz_app.exe";

/// 計測を始める前の構築。成功したら構築したバイナリの由来を返す。
///
/// 失敗を文脈付きで返すのは、構築が失敗した実行を「計測が失敗した」と読み替えないためである。
/// 構築が通らないまま条件列へ進むと、そこに在る前の構築物で測った値が、いま直したはずの版の値として残る。
pub fn 計測用に構築する(コマンド名: &str) -> Result<構築の由来, String> {
    println!("[xtask] {コマンド名}用リリースビルド");
    let 状態 = Command::new("cargo")
        .args(["build", "--release", "-p", "blitz_app"])
        .status()
        .map_err(|誤り| format!("{コマンド名}のリリースビルドでcargoを起動できなかった: {誤り}"))?;
    if !状態.success() {
        return Err(format!(
            "{コマンド名}のリリースビルドが終了コード{状態}で失敗した(直そうとした版で測れないためここで止める)"
        ));
    }
    let 由来 = 構築の由来::採る(Path::new(計測用の実行ファイル));
    println!("[xtask] {コマンド名}の計測に使うバイナリの由来: {}", 由来.一行にする());
    Ok(由来)
}

/// 由来を要らない計測入口のための形。中身は`計測用に構築する`と同じであり、失敗の理由はその場で出す。
pub fn 実行する(コマンド名: &str) -> bool {
    match 計測用に構築する(コマンド名) {
        Ok(_) => true,
        Err(理由) => {
            eprintln!("[xtask] {理由}");
            false
        }
    }
}
