//! 検証用ソースアセットの生成と、生成物のソースアセットの取り揃えの入口。実体はアセットコンパイラの生成器exampleであり、
//! その起こし方は`asset_generator`が持つ。参照: CLAUDE.md「ツールとドキュメントの配置」(xtaskはツールの唯一の入口)。
//!
//! 2つの入口を同じモジュールへ置くのは、どちらも同じ生成器を起こす入口だからである。無条件に起こすのが前者、
//! 欠けているときだけ起こすのが後者であり、後者の中身は`supply`が持つ。

mod supply;

use std::process::ExitCode;

use crate::asset_generator::{アセット生成器の起動, 生成の指定, 生成器エラー};
use supply::生成物のソースアセットを揃える係;

pub fn 検証用ソースアセットを生成する() -> ExitCode {
    if 検証用ソースアセットを生成して成否を返す() {
        ExitCode::SUCCESS
    } else {
        ExitCode::FAILURE
    }
}

pub fn 検証用ソースアセットを生成して成否を返す() -> bool {
    println!("[xtask] 検証用ソースアセットの生成器を実行");
    match 生成器を走らせる() {
        Ok(()) => {
            println!("[xtask] ソースアセット生成成功");
            true
        }
        Err(理由) => {
            eprintln!("[xtask] ソースアセット生成に失敗した: {理由}");
            false
        }
    }
}

fn 生成器を走らせる() -> Result<(), 生成器エラー> {
    アセット生成器の起動::始める(&生成の指定::ソースアセットを生成する {
        場所巡りの世界の種: None,
        ソースルート: None,
        世界の広がり: None,
    })?
    .画面へ流したまま走らせて終わりを待つ()
}

/// 生成物のソースアセットを揃える入口。破れを1行の報せと終了コードへ写すことだけを担当する。
pub fn 生成物のソースアセットを揃える() -> ExitCode {
    if 生成物のソースアセットを揃えて成否を返す() {
        ExitCode::SUCCESS
    } else {
        ExitCode::FAILURE
    }
}

pub fn 生成物のソースアセットを揃えて成否を返す() -> bool {
    match 生成物のソースアセットを揃える係::既定のソースルートで作る().不足していれば生成して揃える() {
        Ok(()) => true,
        Err(破れ) => {
            eprintln!("[xtask] 生成物のソースアセットを揃えられなかった: {破れ}");
            false
        }
    }
}
