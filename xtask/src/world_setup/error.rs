//! 検収の世界の用意が返す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。
//! 様式は`acceptance/error.rs`に倣う。
//!
//! 「焼く工程が失敗した」と「焼いたのに実行時形式が無い」を別の枝で持つのは、直す側が見る場所が違うためである。
//! 前者はコンパイラの出力に理由が出ており、後者は外部のアセットリポジトリが見つからず宣言が飛ばされている。

use std::path::PathBuf;

#[derive(Debug)]
pub enum 検収世界の用意の破れ {
    検証用アセットを生成できなかった {
        世界の呼び名: &'static str,
    },
    実行時形式が作られていない {
        世界の呼び名: &'static str,
        実行時形式のパス: PathBuf,
    },
}

impl std::error::Error for 検収世界の用意の破れ {}

impl std::fmt::Display for 検収世界の用意の破れ {
    fn fmt(&self, 書き手: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::検証用アセットを生成できなかった { 世界の呼び名 } => {
                write!(書き手, "{世界の呼び名}のアセット生成に失敗した")
            }
            Self::実行時形式が作られていない {
                世界の呼び名,
                実行時形式のパス,
            } => write!(
                書き手,
                "{世界の呼び名}の実行時形式{}が作られていない(外部のアセットリポジトリが見つからなかった可能性が高い。compile-assetsの出力に理由が出る)",
                実行時形式のパス.display()
            ),
        }
    }
}
