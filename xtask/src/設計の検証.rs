//! `cargo xtask design-verify` の入口。設計関係グラフを抽出し、その上で構造の法則の命題を検証する(Issue #173「実行入口と検証入口」)。
//!
//! この入口は世界を実行せず、世界について命題を問う。検証の側がゲームロジックを再実装しないため、
//! 問う相手は実装から組んだ設計関係グラフだけである。
//! **振る舞いの命題はこの入口が検証しない。** 振る舞いの命題は実物の遷移関数を呼ばなければ検証できず、
//! 呼ぶには `xtask` がドメインのクレートへ依存する必要がある。振る舞いの命題を検証するのはドメインのクレートの試験であり、
//! そのための語彙は `blitz_design_verification` の `有限に数え上げられる領域` が渡す(Issue #174 のオーナー裁定)。
//! **反証済み・未決定・命題の集合が問う答えを弱める抽出の欠落のどれかが1件でもあれば終了コードを非0にする**(2026-09-27。Issue #175 の第1段階の検収で親が採った指摘)。
//! 未決定と欠落を合格へ写すと、抽出が関係を落としたり検証器が答えを弱めたりしたときに、公理が何も確かめないまま検証が通る。
//! ゲートが黙って無効になるこの経路を塞ぐため、未決定と欠落も不合格にする。欠落は、命題の集合が問う答え(`命題の集合::問う答え一覧`)を弱めるものだけを数える
//! (Issue #175 の第2段階の親の判断)。どの命題も問わない答えだけを弱める欠落は、件数と理由を表示し、合否に効かないことをその表示に書く。
//! いまの命題の集合は全ての処理を量化する法則を含むため全ての答えを問い、合否に効かない欠落は0件である。
//! **命題を1件も検証しなかった実行は非0にする。** これは受理の規則ではなく、検査器が1件も検査していない実行を
//! 合格として答えないという別の規約である。何も検証していないことを合格として答えると、命題の集合が空になった事故が
//! 検証に通った状態と見分けられない。
//! 未決定を0件として隠さないのは、検査器が解けなかった入力を黙って対象から外してはならないためである
//! (グローバルCLAUDE.md「検査器は解析できなかった入力を黙って対象から外してはならない」)。
//! 抽出の内訳の後に表示する設計関係への参加の計測は、命題の母集団を裁定するための材料であり、命題へ接続しない(Issue #187)。
//! その次に表示する関数の署名の計測も、遷移の形をしているのに関数の役割の宣言が漏れている関数を見つける法則の材料であり、命題へ接続しない(Issue #175)。
//! 構造の法則の検証の結果は、計測の区画と別の見出しの下に出す。

use std::process::ExitCode;

use blitz_design_verification::{命題の集合, 検証の集計, 構造の検証器, 関係を落とした抽出の欠落};

use crate::設計関係のモデル::設計関係グラフを抽出する;
use 設計の検証の合否::検証結果の件数;

#[path = "設計の検証/抽出の内訳の表示.rs"]
mod 抽出の内訳の表示;
#[path = "設計の検証/構造の法則.rs"]
mod 構造の法則;
#[path = "設計の検証/設計の検証の合否.rs"]
mod 設計の検証の合否;
#[path = "設計の検証/設計関係への参加の計測.rs"]
mod 設計関係への参加の計測;
#[path = "設計の検証/関数の署名の計測.rs"]
mod 関数の署名の計測;

pub fn 設計の命題を検証する() -> ExitCode {
    let 抽出したもの = match 設計関係グラフを抽出する() {
        Ok(抽出したもの) => 抽出したもの,
        Err(破れ) => {
            eprintln!("[xtask] design-verify: 設計関係グラフを抽出できなかった: {破れ}");
            return ExitCode::FAILURE;
        }
    };
    let mut 件数 = 検証結果の件数::default();
    println!("[xtask] design-verify: 設計関係グラフの内訳");
    抽出の内訳の表示::抽出の内訳を表示する(&抽出したもの);
    let 命題の集合 = 構造の法則::構造の法則の命題の集合を組む();
    let 欠落 = 抽出したもの.関係を落とした抽出の欠落へ写す();
    let 問う答えを弱める件数 = 件数.命題が問う答えを弱める欠落を取り込む(&欠落, &命題の集合);
    欠落の件数を表示する(&欠落, &命題の集合, 問う答えを弱める件数);
    println!("[xtask] design-verify: 設計関係へ参加していない概念の計測");
    print!("{}", 設計関係への参加の計測::設計関係への参加の計測::計測する(&抽出したもの, &欠落));
    println!("[xtask] design-verify: 関数の署名の計測");
    print!("{}", 関数の署名の計測::関数の署名の計測::計測する(&抽出したもの));
    let グラフの検証器 = 構造の検証器::生成する(&抽出したもの.グラフ, 欠落);
    件数.構造の集計を取り込む(&構造の法則を検証して表示する(&命題の集合, &グラフの検証器));
    件数.結果を表示して終了コードを答える()
}

// 欠落の件数を検証の前に表示する。表示しないと、検証器が不在を根拠にしてよいかの判断材料が読み手に見えない。
// 問わない答えだけを弱める件を別に数えて出すのは、その件が合否に効かないことを読み手が確かめられるようにするためである。
fn 欠落の件数を表示する(欠落: &関係を落とした抽出の欠落, 命題の集合: &命題の集合, 問う答えを弱める件数: usize) {
    println!("  {}", 欠落.説明());
    let 問う答え一覧 = 命題の集合.問う答え一覧();
    let 語一覧: Vec<&str> = 問う答え一覧.iter().map(|答え| 答え.語()).collect();
    println!("  うち、命題の集合が問う答え({})を弱める欠落は{問う答えを弱める件数}件である", 語一覧.join("・"));
    let 問わない件数 = 欠落.合計の件数() - 問う答えを弱める件数;
    println!("  残りの{問わない件数}件は、どの命題も問わない答えだけを弱めるため、合否に効かない");
}

// 構造の法則の命題の集合を検証し、結果と反例の割り当てと未決定の理由を表示して、集計を答える。
fn 構造の法則を検証して表示する(命題の集合: &命題の集合, 検証器: &構造の検証器<'_>) -> 検証の集計 {
    let 集計 = 命題の集合.全件を検証する(検証器);
    // 見出しを分けるのは、構造の法則の結果が上の計測の区画の一部として読まれないためである。計測は命題へ接続していない。
    println!("[xtask] design-verify: 構造の法則の検証");
    println!("  構造の法則: {}", 集計.表記());
    for (名前, 反例) in &集計.反証済みの一覧 {
        println!("    反証済み: {名前}: {}", 反例.説明);
        // 反例の割り当て(どの型が公理を破ったか)を出す。説明の文だけでは、どの型を直せばよいかを読み手が決められない。
        for (束縛, 概念) in &反例.再現の材料 {
            println!("      {束縛} = {概念}");
        }
    }
    // 未決定の理由を件数だけで済ませない。何を解けなかったかを読めないと、抽出の欠落で未決定へ落ちた命題と
    // この検証器が扱わない命題を読み手が区別できない。
    for (名前, 理由) in &集計.未決定の一覧 {
        println!("    未決定: {名前}: {理由:?}");
    }
    集計
}
