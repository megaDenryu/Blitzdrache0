//! 判定の結果を人が読む1文へ組む工程。受け取るのは条件ごとの結果と帯の実測、返すのは要約の文字列である。
//! 判定そのものは`judgment`と`band`が済ませており、この工程は数を並べるだけを担う。

use super::band::帯の実測;
use super::conditions::条件の結果;

pub(super) struct 要約の材料<'a> {
    pub(super) 拡散: &'a 条件の結果,
    pub(super) 段別: &'a 条件の結果,
    pub(super) 面別: &'a 条件の結果,
    pub(super) 面別の別方位: &'a 条件の結果,
    pub(super) 縦結合: &'a 条件の結果,
    pub(super) 黒に落ちた金属: usize,
    pub(super) 面の最小余裕: f64,
    pub(super) 覆った面: &'a [u32],
    pub(super) 帯: &'a 帯の実測,
}

pub(super) fn 要約を組む(材料: &要約の材料<'_>) -> String {
    format!(
        "拡散だけの条件で板{}枚が一致し(最大{:.2}符号値差)金属{}枚が黒に落ち、鏡面の段別で板{}枚が一致し(最大{:.2})粗さが整数の段を選び、鏡面の面別が2つの時刻で板{}枚と{}枚一致し(最大{:.2}と{:.2})面{:?}の6面を覆い面の端からの余裕が最小{:.4}、縦結合で板{}枚が一致し(最大{:.2})、注入なしの昼の描画で板の領域{}画素の飽和割合{:.4}・黒潰れ割合{:.4}、6つの実行すべてでvalidation0件",
        材料.拡散.板数,
        材料.拡散.最大符号値差,
        材料.黒に落ちた金属,
        材料.段別.板数,
        材料.段別.最大符号値差,
        材料.面別.板数,
        材料.面別の別方位.板数,
        材料.面別.最大符号値差,
        材料.面別の別方位.最大符号値差,
        材料.覆った面,
        材料.面の最小余裕,
        材料.縦結合.板数,
        材料.縦結合.最大符号値差,
        材料.帯.画素数,
        材料.帯.飽和割合,
        材料.帯.黒潰れ割合
    )
}
