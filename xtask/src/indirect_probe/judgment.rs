//! 板の行に対する判定。受け取るのは条件名と板の行の一覧、返すのは判定に使った代表値である。
//!
//! 許容を8bitの符号値で置くのは、判定する値がsRGB符号化後の読み戻し画像だからである。線形の相対誤差で置くと、
//! 暗い板では1符号値の丸めが巨大な相対誤差に見え、明るい板では大きな式の誤りが小さな相対誤差に埋もれる。
//!
//! 鏡面の板が黒でないことだけを真偽で課すのは、その比べが「全成分が許容以下」の否定であり、上限と下限の口の
//! どちらにも当てはまらないためである。成分の並びに対する述語をそのまま保つ。

use super::parse::板の行;
use crate::acceptance::{判定の名前, 判定の破れ};

/// 期待と実測の許容差(8bitの符号値)。半精度の丸めを吸収する幅であり、式の誤りはこの幅では説明できない大きさで出る。
const 符号値の許容: f64 = 4.0;

/// 縮小段の位置が整数からずれてよい量。板の粗さは段へ正確に合わせてあるため、ずれは丸めのぶんしかない。
const 段の位置の許容: f64 = 1.0e-4;

pub(super) struct 判定 {
    pub(super) 最大符号値差: f64,
    pub(super) 板数: usize,
}

pub(super) fn 期待と実測の一致を検査する(条件名: &str, 一覧: &[板の行]) -> Result<判定, 判定の破れ> {
    let mut 最大符号値差: f64 = 0.0;
    for 行 in 一覧 {
        let 板の中の最大 = (0..3).map(|軸| (行.期待[軸] - 行.実測[軸]).abs()).fold(f64::NEG_INFINITY, f64::max);
        最大符号値差 = 最大符号値差.max(板の中の最大);
        期待と実測の隔たりの判定名(条件名, 行).上限を課す(板の中の最大, 符号値の許容)?;
    }
    Ok(判定 {
        最大符号値差,
        板数: 一覧.len(),
    })
}

/// 金属の板は拡散の取り分が0になるため、拡散だけを立てた条件では黒に落ちる。落ちないなら取り分を掛けていない。
///
/// 同じ画素が鏡面の条件では黒でないことを対にして見るのは、黒を「板がそもそも描かれていない」と読み替えないためである。
/// 板が写っていなければ拡散の条件でも黒くなり、取り分の判定が中身なしで通る。
pub(super) fn 金属が黒に落ちることを検査する(拡散: &[板の行], 鏡面: &[板の行]) -> Result<usize, 判定の破れ> {
    let 金属の板 = 1..=6;
    let mut 件数 = 0;
    for 行 in 拡散.iter().filter(|行| 金属の板.contains(&行.番号)) {
        黒に落ちた金属の判定名(行).上限を課す(成分の最大(&行.実測), 符号値の許容)?;
        let 対の判定名 = 鏡面の対の判定名(行);
        let 対 = 鏡面
            .iter()
            .find(|対| 対.番号 == 行.番号)
            .ok_or_else(|| 対の判定名.あるはずのものが無い破れ())?;
        対の判定名.真であることを課す(!対.実測.iter().all(|値| *値 <= 符号値の許容))?;
        件数 += 1;
    }
    Ok(件数)
}

/// 板の粗さが縮小段へ正確に対応していることを見る。対応が崩れると、判定が段の間の混ざりを見ることになる。
pub(super) fn 段が整数であることを検査する(一覧: &[板の行]) -> Result<(), 判定の破れ> {
    for 行 in 一覧 {
        let ずれ = (行.段の位置 - 行.段の位置.round()).abs();
        段の位置の判定名(行).上限を課す(ずれ, 段の位置の許容)?;
    }
    Ok(())
}

/// 3成分のうち最も大きいもの。非数は`f64::max`が退けるため、成分ごとの比べと同じ結果になる。
fn 成分の最大(実測: &[f64; 3]) -> f64 {
    実測.iter().copied().fold(f64::NEG_INFINITY, f64::max)
}

fn 期待と実測の隔たりの判定名(条件名: &str, 行: &板の行) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}の板{}の期待{:?}と実測{:?}の隔たり", 行.番号, 行.期待, 行.実測))
}

fn 黒に落ちた金属の判定名(行: &板の行) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "拡散だけの条件での金属の板{}の実測{:?}の最大成分(黒に落ちていないなら拡散の取り分を掛けていない)",
        行.番号, 行.実測
    ))
}

fn 鏡面の対の判定名(行: &板の行) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("鏡面の条件の板{}が黒でないこと(黒なら板が描かれていない疑いがある)", 行.番号))
}

fn 段の位置の判定名(行: &板の行) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("板{}の縮小段の位置{:.6}の整数からのずれ", 行.番号, 行.段の位置))
}
