//! 破綻防止帯の判定。受け取るのは注入なしで描いた読み戻し画像、返すのは飽和と黒潰れの画素の割合である。
//!
//! 注入を外した実行で測るのは、この帯が「大気から焼いた遠方環境で本番と同じ経路を通したときに絵が壊れていないか」
//! を見るものだからである。注入した条件は判定のために金属を黒へ落とすなど極端な値を作るため、帯の対象にならない。
//!
//! 帯の閾値と割合の上限は`xtask/src/damage_band.rs`が持つ台帳から引く。帯を広く取る理由もその台帳が述べており、
//! 明るさの自然さはオーナーの目視に残して機械条件は破綻の有無だけを見る。

use crate::acceptance::{判定の名前, 判定の破れ, 画素の横位置, 画素の縦位置, 読み戻し画像};
use crate::damage_band::{割合にする, 飽和の下限, 飽和割合の上限, 黒潰れの上限, 黒潰れ割合の上限};
use crate::pixel_region::画面領域;

const 破綻防止帯の判定領域の画素: 判定の名前 = 判定の名前::定数から生成する("破綻防止帯の判定領域の画素");
const 板の領域の飽和画素の割合: 判定の名前 = 判定の名前::定数から生成する("板の領域の飽和画素の割合");
const 板の領域の黒潰れ画素の割合: 判定の名前 = 判定の名前::定数から生成する("板の領域の黒潰れ画素の割合");

/// 板が並ぶ範囲を覆う判定領域の、画面の幅と高さに対する割合。板は画面中央の4列2行に並ぶ。
const 領域の左: f64 = 0.25;
const 領域の右: f64 = 0.75;
const 領域の上: f64 = 0.30;
const 領域の下: f64 = 0.70;

pub(super) struct 帯の実測 {
    pub(super) 飽和割合: f64,
    pub(super) 黒潰れ割合: f64,
    pub(super) 画素数: u64,
}

pub(super) fn 破綻防止帯を検査する(画像: &読み戻し画像) -> Result<帯の実測, 判定の破れ> {
    let 領域 = 判定領域を作る(画像);
    let 画素数 = 領域.画素数();
    if 画素数 == 0 {
        return Err(破綻防止帯の判定領域の画素.あるはずのものが無い破れ());
    }
    let 飽和 = 全成分が範囲内の画素を数える(画像, &領域, 飽和の下限, u8::MAX);
    let 黒潰れ = 全成分が範囲内の画素を数える(画像, &領域, 0, 黒潰れの上限);
    let 実測 = 帯の実測 {
        飽和割合: 割合にする(飽和, 画素数),
        黒潰れ割合: 割合にする(黒潰れ, 画素数),
        画素数,
    };
    板の領域の飽和画素の割合.上限を課す(実測.飽和割合, 飽和割合の上限)?;
    板の領域の黒潰れ画素の割合.上限を課す(実測.黒潰れ割合, 黒潰れ割合の上限)?;
    Ok(実測)
}

fn 判定領域を作る(画像: &読み戻し画像) -> 画面領域 {
    let 横 = |割合: f64| 割合を画素へ(割合, 画像.幅().画素数());
    let 縦 = |割合: f64| 割合を画素へ(割合, 画像.高さ().画素数());
    画面領域 {
        x開始: 横(領域の左),
        x終端: 横(領域の右),
        y開始: 縦(領域の上),
        y終端: 縦(領域の下),
    }
}

fn 割合を画素へ(割合: f64, 画素数: usize) -> usize {
    let 実数 = 割合 * 画素数を実数へ(画素数);
    let mut 位置 = 0usize;
    while 画素数を実数へ(位置 + 1) <= 実数 && 位置 < 画素数 {
        位置 += 1;
    }
    位置
}

fn 画素数を実数へ(値: usize) -> f64 {
    f64::from(u32::try_from(値).unwrap_or(u32::MAX))
}

/// 3成分すべてが範囲に入る画素を数える。明度1成分だけを見る`pixel_region`と別に持つのは、
/// 飽和も黒潰れも3成分そろっていることを条件にするためである。
fn 全成分が範囲内の画素を数える(画像: &読み戻し画像, 領域: &画面領域, 下限: u8, 上限: u8) -> u64 {
    let mut 件数 = 0u64;
    for y in 領域.y開始..領域.y終端 {
        for x in 領域.x開始..領域.x終端 {
            let 色 = 画像.座標の画素(画素の横位置::生成する(x), 画素の縦位置::生成する(y));
            if 色.iter().all(|成分| *成分 >= 下限 && *成分 <= 上限) {
                件数 += 1;
            }
        }
    }
    件数
}
