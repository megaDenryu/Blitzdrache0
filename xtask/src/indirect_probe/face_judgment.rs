//! 鏡面の面別の条件だけが要る判定。受け取るのは板の行の一覧、返すのは面の端からの最小余裕と覆った面の一覧である。
//!
//! 期待と実測の一致の判定と分けるのは、見る対象が違うためである。あちらは値そのものを見るのに対し、
//! こちらは「どの面を参照したか」という参照先の性質だけを見る。

use super::parse::板の行;

/// 面の端からの余裕の下限。立方体の補間が隣の面を混ぜない距離を確保する。
const 面の端からの余裕の下限: f64 = 0.05;

/// 参照した面が境界へ寄っていないことを見る。寄っていると立方体の補間が隣の面を混ぜ、面ごとの色の判定が成り立たない。
pub(super) fn 面の余裕を検査する(一覧: &[板の行]) -> Result<f64, String> {
    let mut 最小余裕 = f64::MAX;
    for 行 in 一覧 {
        最小余裕 = 最小余裕.min(行.面の端からの余裕);
        if 行.面の端からの余裕 < 面の端からの余裕の下限 {
            return Err(format!(
                "板{}が参照する面の端からの余裕{:.4}が下限{面の端からの余裕の下限}を下回った",
                行.番号, 行.面の端からの余裕
            ));
        }
    }
    Ok(最小余裕)
}

/// 2つの実行が参照した面の合併。立方体の6面すべてを覆っていなければ失敗にする。
pub(super) fn 立方体の6面を覆うことを検査する(一覧一覧: &[&[板の行]]) -> Result<Vec<u32>, String> {
    let mut 覆った面 = Vec::new();
    for 一覧 in 一覧一覧 {
        for 行 in *一覧 {
            if !覆った面.contains(&行.面) {
                覆った面.push(行.面);
            }
        }
    }
    覆った面.sort_unstable();
    if 覆った面.len() != 6 {
        return Err(format!(
            "参照した面が{:?}の{}種類しかない(6面すべてを覆う必要がある)",
            覆った面,
            覆った面.len()
        ));
    }
    Ok(覆った面)
}
