//! 1条件ぶんの実行と判定をひとまとめに通す工程。受け取るのは出力先と条件の指定、返すのは板の行と判定の代表値である。
//! 起動は`run`、行の取り出しは`parse`、合否は`judgment`が担い、この工程はその3つを順に通すことだけを担う。

use super::run::注入の指定;
use super::{band, judgment, parse, run};
use crate::acceptance::{描画検収の実行環境, 検収の実行名, 検収エラー};

/// 破綻防止帯を測る実行の書き出しの基準名。
const 破綻防止帯の実行名: 検収の実行名 = 検収の実行名::定数から生成する("band");

/// 1条件ぶんの判定結果。
pub(super) struct 条件の結果 {
    pub(super) 行一覧: Vec<parse::板の行>,
    pub(super) 最大符号値差: f64,
    pub(super) 板数: usize,
}

pub(super) fn 条件を判定する(
    実行環境: &描画検収の実行環境,
    実行名の綴り: &str,
    条件: &str,
    一日内秒: &str,
) -> Result<条件の結果, 検収エラー> {
    let 結果 = 実行環境.描いて読み戻す(
        検収の実行名::生成する(実行名の綴り)?,
        &run::起動指定を組み立てる(一日内秒, &注入の指定::注入する(条件), false),
    )?;
    let 行一覧 = parse::板の行を取り出す(結果.報告())?;
    let 判定 = judgment::期待と実測の一致を検査する(実行名の綴り, &行一覧)?;
    Ok(条件の結果 {
        行一覧,
        最大符号値差: 判定.最大符号値差,
        板数: 判定.板数,
    })
}

pub(super) fn 破綻防止帯を測る(
    実行環境: &描画検収の実行環境, 昼の一日内秒: &str
) -> Result<band::帯の実測, 検収エラー> {
    let 結果 = 実行環境.描いて読み戻す(
        破綻防止帯の実行名,
        &run::起動指定を組み立てる(昼の一日内秒, &注入の指定::大気から焼く, true),
    )?;
    Ok(band::破綻防止帯を検査する(結果.画像())?)
}
