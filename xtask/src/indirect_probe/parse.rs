//! blitz_appが出した板ごとの照合行を数の並びへ直す工程。受け取るのは終了時報告、返すのは板の行の一覧である。
//! 判定はこの並びだけを見る。
//!
//! 行が1本も無いことを失敗にするのは、注入も報告も行われなかった実行を「全項目が通った」と読み替えないためである。
//!
//! 照合できなかった板を行の原文から探すのは、その行が期待と実測の項を持たないためである。鍵で読もうとすると、
//! 「照合できなかった」でなく「期待の鍵が無い」という別の理由で落ちる。

use crate::acceptance::{判定の名前, 報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

/// 板1枚ぶんの照合結果。
pub(super) struct 板の行 {
    pub(super) 番号: usize,
    pub(super) 期待: [f64; 3],
    pub(super) 実測: [f64; 3],
    pub(super) 面: u32,
    pub(super) 段の位置: f64,
    pub(super) 面の端からの余裕: f64,
}

const 行の見出し: 報告の見出し = 報告の見出し::定数から生成する("間接照明代表板 ");
/// 板を照合できなかった実行の行に現れる綴り。正本はblitz_appの間接照明の報告である。
const 照合できなかったことの綴り: &str = "照合できなかった";
/// この報告の行は全項目が「鍵=値」の形で並ぶ。
const 値の結ばれ方: 鍵に値が結ばれる形 = 鍵に値が結ばれる形::等号の後ろが値である;

const 板の照合行: 判定の名前 = 判定の名前::定数から生成する("板の照合行");

pub(super) fn 板の行を取り出す(報告: &終了時報告) -> Result<Vec<板の行>, 検収エラー> {
    let mut 一覧 = Vec::new();
    for 行 in 報告.見出しで始まる行の一覧(&行の見出し) {
        照合できなかった板の判定名(&行).零件であることを課す(u64::from(行.原文().contains(照合できなかったことの綴り)))?;
        一覧.push(板の1行を読む(&行)?);
    }
    if 一覧.is_empty() {
        return Err(板の照合行.あるはずのものが無い破れ().into());
    }
    Ok(一覧)
}

fn 板の1行を読む(行: &報告の行) -> Result<板の行, 検収エラー> {
    Ok(板の行 {
        番号: 数を読む(行, "番号")?,
        期待: 色の3成分を読む(行, "期待")?,
        実測: 色の3成分を読む(行, "実測")?,
        面: 数を読む(行, "面")?,
        段の位置: 数を読む(行, "段")?,
        面の端からの余裕: 数を読む(行, "面余裕")?,
    })
}

fn 数を読む<数: std::str::FromStr>(行: &報告の行, 鍵の綴り: &str) -> Result<数, 検収エラー> {
    行.鍵に結ばれた数(&鍵を組む(鍵の綴り), 値の結ばれ方)
}

/// 「期待=0.1,0.2,0.3」の形で1つの語に並ぶ3成分。成分の切り方をこの1箇所だけが知る。
fn 色の3成分を読む(行: &報告の行, 鍵の綴り: &str) -> Result<[f64; 3], 検収エラー> {
    let 語 = 行.鍵に結ばれた綴り(&鍵を組む(鍵の綴り), 値の結ばれ方)?;
    let 判定名 = 成分の判定名(鍵の綴り, &語);
    let mut 成分一覧: Vec<f64> = Vec::new();
    for 成分 in 語.split(',') {
        成分一覧.push(判定名.材料を数として読む(成分)?);
    }
    判定名.一致を課す(成分一覧.len(), 3)?;
    Ok([成分一覧[0], 成分一覧[1], 成分一覧[2]])
}

fn 鍵を組む(綴り: &str) -> 報告の行の鍵 {
    報告の行の鍵::組み立てた綴りから生成する(綴り.to_string())
}

fn 成分の判定名(鍵の綴り: &str, 語: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("板の照合行の{鍵の綴り}の3成分(値は{語})"))
}

/// 照合できなかった行そのものを綴りへ入れるのは、blitz_appが照合できなかった理由をその行に書いているためである。
fn 照合できなかった板の判定名(行: &報告の行) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("照合できなかった板(行「{}」)", 行.原文()))
}
