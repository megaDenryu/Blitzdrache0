//! 検収1条件ぶんの起動の指定。受け取るのは一日内秒と注入の指定とポスト処理の有無、返すのは実行環境へ渡す
//! 起動指定である。起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! ポスト処理を切るのは、期待値を閉じた式で作るためである。スワップチェーンの形式がsRGBであるため、
//! ポスト処理を外した実行の書き込みは「線形の放射輝度を0から1へ切り詰めてsRGB符号化した値」そのものになる。
//! 光のにじみと明るさの圧縮を通すと、周囲の明るさが混ざって1画素の期待値が決まらない。
//!
//! 空パスを外すのは、背景が判定に要らないためである。板の画素だけを読むため背景は何であってもよく、
//! 空パスを積まないほうが実行が短い。間接照明の方針は`--no-sky`では動かない。

use std::path::PathBuf;

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収エラー, 検収シーン名
};

const アセットルート: &str = "target/runtime_assets";
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(12);
pub(super) const シーンの綴り: &str = "indirect_probe";
const シーン名: 検収シーン名 = 検収シーン名::生成する(シーンの綴り);

/// そのフレームで解析入力を注入するかどうか。注入しない実行は大気から焼いた遠方環境で描く。
pub(super) enum 注入の指定<'a> {
    注入する(&'a str),
    大気から焼く,
}

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::綴りから生成する(アセットルート),
        出力ディレクトリ,
    )
}

pub(super) fn 起動指定を組み立てる(
    一日内秒: &str, 注入: &注入の指定<'_>, ポスト処理を通すか: bool
) -> アプリの起動指定 {
    let mut 指定 = アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数)
        .値を持つ選択肢を足す("--time-of-day", 一日内秒)
        .選択肢をまとめて足す(&["--no-sky", "--report-memory"]);
    if !ポスト処理を通すか {
        指定 = 指定.選択肢を足す("--no-post");
    }
    if let 注入の指定::注入する(条件) = 注入 {
        指定 = 指定.値を持つ選択肢を足す("--indirect-probe", 条件);
    }
    指定
}
