//! 背景色の決定と、ある画素が背景と同じ色かの判定。触れるのは読み戻し画像の4隅だけであり、物体の広がりは見ない。
//!
//! 背景色を定数で持たずに隅の画素から採るのは、読み戻し画像がクリア色をどう符号化するかを検収側が写しで持たないためである。
//! 写しを持つと、クリア色や色空間の変更でこの検収だけが無言で通らなくなる。

use crate::acceptance::{
    判定が比べる値, 判定の名前, 判定の破れ, 判定の破れの種類, 画素の横位置, 画素の縦位置, 読み戻し画像
};

/// 隅として読む位置の、辺からの距離。境界の1画素は隣接パスの縁が乗りうるため内側へ寄せる。
const 隅の内寄せ: usize = 3;
/// 背景と同じ色とみなす成分ごとの差。読み戻しの符号化で1階調の揺れが出ても背景を物体と数えないための幅である。
const 背景とみなす差: u8 = 2;

const 隅を読むための辺の長さ: 判定の名前 = 判定の名前::定数から生成する("背景色を採る4隅を読むための読み戻し画像の辺");
const 四隅の色: 判定の名前 = 判定の名前::定数から生成する("読み戻し画像の4隅の色");

/// 4隅の画素から背景色を決める。4隅が一致しないなら背景が一様でなく、この検収の前提が成り立たない。
pub(super) fn 決める(画像: &読み戻し画像) -> Result<[u8; 3], 判定の破れ> {
    let 辺を読める最小の長さ = 隅の内寄せ * 2 + 1;
    隅を読むための辺の長さ.下限を課す(画像.幅().画素数(), 辺を読める最小の長さ)?;
    隅を読むための辺の長さ.下限を課す(画像.高さ().画素数(), 辺を読める最小の長さ)?;
    let 右 = 画像.幅().画素数() - 1 - 隅の内寄せ;
    let 下 = 画像.高さ().画素数() - 1 - 隅の内寄せ;
    let 隅一覧 = [
        画像.座標の画素(画素の横位置::生成する(隅の内寄せ), 画素の縦位置::生成する(隅の内寄せ)),
        画像.座標の画素(画素の横位置::生成する(右), 画素の縦位置::生成する(隅の内寄せ)),
        画像.座標の画素(画素の横位置::生成する(隅の内寄せ), 画素の縦位置::生成する(下)),
        画像.座標の画素(画素の横位置::生成する(右), 画素の縦位置::生成する(下)),
    ];
    let 基準 = 隅一覧[0];
    if 隅一覧.iter().all(|隅| 同じ色か(*隅, 基準)) {
        return Ok(基準);
    }
    Err(四隅の色.破れを組む(判定の破れの種類::一致するはずが食い違った {
        実測: 判定が比べる値::綴り(format!("{隅一覧:?}")),
        期待: 判定が比べる値::綴り(format!("4隅とも{基準:?}")),
    }))
}

pub(super) fn 同じ色か(色: [u8; 3], 基準: [u8; 3]) -> bool {
    色.iter()
        .zip(基準.iter())
        .all(|(成分, 基準成分)| 成分.abs_diff(*基準成分) <= 背景とみなす差)
}
