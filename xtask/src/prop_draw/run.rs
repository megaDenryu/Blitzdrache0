//! 検収1条件ぶんの起動の指定。受け取るのは条件、返すのは実行環境へ渡す起動指定である。
//! 起こす手順そのものは検収の共通語彙の実行環境が持ち、ここは条件ごとに違う選択肢だけを決める。
//!
//! 小物のシーンは板の世界の宣言に並ぶため、実行時アセットルートは`compile-assets`の既定と同じ場所を渡す。
//! シーン名を`prop_`で始めることが、小物を斜めから見る初期カメラと、書き換えもピクセル判定も持たない検収計画を選ばせる。
//! 監視対象シェーダーは指定しない。指定しないと埋め込みシェーダーで走り、リポジトリの`shaders/`へ監視の入口が向かない。

use std::path::PathBuf;

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収の実行名, 検収エラー, 検収シーン名,
};

const アセットルート: &str = "target/runtime_assets";
/// 2条件の書き出しの基準名。絵のファイル名になり、失敗の文面もこの名前で実行を名指す。
pub(super) const ポストなしの実行名: 検収の実行名<'static> = 検収の実行名::定数から生成する("flat");
pub(super) const 本番経路の実行名: 検収の実行名<'static> = 検収の実行名::定数から生成する("post");
const シーン名: 検収シーン名 = 検収シーン名::生成する("prop_wooden_crate");
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(120);

#[derive(Clone, Copy)]
pub(super) enum 条件 {
    /// ポスト処理を含む本番の経路。絵の目視はこの条件から採る。
    本番経路,
    /// ポスト処理を外した経路。光のにじみが背景へ回り込まないため、背景がクリア色のままであることを前提に画素を数えられる。
    ポストなし,
}

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::綴りから生成する(アセットルート),
        出力ディレクトリ,
    )
}

pub(super) fn 起動指定を組み立てる(条件: 条件) -> アプリの起動指定 {
    let 指定 = アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数);
    match 条件 {
        条件::本番経路 => 指定,
        条件::ポストなし => 指定.選択肢を足す("--no-post"),
    }
}
