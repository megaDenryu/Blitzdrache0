//! 小物が絵として成立していることの機械判定。受け取るのは読み戻し画像、返すのは合格の要約である。
//! 判定は4つの破れ方を弾く。何も描かれていない、画面全体が塗られている、物体が構図の中央に無い、
//! 面の明るさが一様で立体に見えない、の4つである。
//!
//! 絵としての見た目の合否は親エージェントの目視が決める。ここが担うのは、目視の前に「絵が出ていない」種類の
//! 壊れ方を機械で落とすことだけである。囲む矩形の位置と広がりの判定は`bounding_box_judgment`が持つ。

use super::background_color;
use super::bounding_box_judgment;
use super::object_pixels::{物体画素の要約, 要約する};
use crate::acceptance::{判定の名前, 検収エラー, 画素の占める割合, 読み戻し画像};

/// 物体が占める画素の割合の許容範囲。下限は物体が写っていることの下支え、上限は背景が残っていることの下支えである。
const 占有率の下限: f64 = 0.02;
const 占有率の上限: f64 = 0.60;
/// 面ごとの明るさの差の下限(8bitの階調)。同じ材質の3面が違う角度で方向光を受けるため、平坦な塗りにはならない。
const 明度の幅の下限: u8 = 20;

const 背景色でない画素: 判定の名前 = 判定の名前::定数から生成する("背景色でない画素");
const 物体が占める割合: 判定の名前 = 判定の名前::定数から生成する("物体が占める割合");
const 面ごとの明るさの差: 判定の名前 = 判定の名前::定数から生成する("面ごとの明るさの差");

pub(super) fn 画素を判定する(画像: &読み戻し画像) -> Result<String, 検収エラー> {
    let 背景色 = background_color::決める(画像)?;
    let 物体画素の要約::物体あり {
        件数,
        矩形,
        明度最小,
        明度最大,
    } = 要約する(画像, 背景色)
    else {
        return Err(背景色でない画素.あるはずのものが無い破れ().into());
    };

    let 占有率 = 画素の占める割合::部分と全体から求める(件数, 画像.画素数())?;
    物体が占める割合.許容の範囲を課す(占有率.値(), 占有率の下限, 占有率の上限)?;
    bounding_box_judgment::画面の中での位置と広がりを判定する(&矩形, 画像)?;
    let 明度の幅 = 明度最大 - 明度最小;
    面ごとの明るさの差.下限を課す(明度の幅, 明度の幅の下限)?;
    Ok(format!(
        "背景色{背景色:?}、物体画素{件数}(占有率{:.4})、囲む矩形x{}から{}・y{}から{}、明度{明度最小}から{明度最大}",
        占有率.値(),
        矩形.x最小,
        矩形.x最大,
        矩形.y最小,
        矩形.y最大
    ))
}
