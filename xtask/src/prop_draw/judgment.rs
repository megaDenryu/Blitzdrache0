//! 小物が絵として成立していることの機械判定。受け取るのは読み戻し画像、返すのは合格の要約である。
//! 判定は4つの破れ方を弾く。何も描かれていない、画面全体が塗られている、物体が構図の中央に無い、
//! 面の明るさが一様で立体に見えない、の4つである。
//!
//! 絵としての見た目の合否は親エージェントの目視が決める。ここが担うのは、目視の前に「絵が出ていない」種類の
//! 壊れ方を機械で落とすことだけである。

use super::background_color;
use super::object_pixels::{囲む矩形, 物体画素の要約, 要約する};
use crate::acceptance::読み戻し画像;

/// 物体が占める画素の割合の許容範囲。下限は物体が写っていることの下支え、上限は背景が残っていることの下支えである。
const 占有率の下限: f64 = 0.02;
const 占有率の上限: f64 = 0.60;
/// 囲む矩形が画面の辺に対して占める割合の上限。これを超えると物体が画面から溢れており、境界箱の全体が写っていない。
const 矩形の辺の上限: f64 = 0.85;
/// 囲む矩形の中心が画面中央からずれてよい割合。カメラは物体の体積の中心を注視するため、構図の中央に来る。
const 中心のずれの上限: f64 = 0.12;
/// 面ごとの明るさの差の下限(8bitの階調)。同じ材質の3面が違う角度で方向光を受けるため、平坦な塗りにはならない。
const 明度の幅の下限: u8 = 20;

pub(super) fn 画素を判定する(画像: &読み戻し画像) -> Result<String, String> {
    let 背景色 = background_color::決める(画像)?;
    let 物体画素の要約::物体あり {
        件数,
        矩形,
        明度最小,
        明度最大,
    } = 要約する(画像, 背景色)
    else {
        return Err(format!("背景色{背景色:?}でない画素が1つも無い。物体が描かれていない"));
    };

    let 全画素数 = 画像.画素数();
    let 占有率 = 割合を求める(件数, 全画素数)?;
    if !(占有率の下限..=占有率の上限).contains(&占有率) {
        return Err(format!(
            "物体が占める割合{占有率:.4}が許容範囲{占有率の下限}以上{占有率の上限}以下から外れた"
        ));
    }
    矩形を判定する(&矩形, 画像.幅().画素数(), 画像.高さ().画素数())?;
    let 明度の幅 = 明度最大 - 明度最小;
    if 明度の幅 < 明度の幅の下限 {
        return Err(format!(
            "面ごとの明るさの差{明度の幅}が下限{明度の幅の下限}に届かない。立体でなく平坦な塗りとして写っている"
        ));
    }
    Ok(format!(
        "背景色{背景色:?}、物体画素{件数}(占有率{占有率:.4})、囲む矩形x{}から{}・y{}から{}、明度{明度最小}から{明度最大}",
        矩形.x最小, 矩形.x最大, 矩形.y最小, 矩形.y最大
    ))
}

/// 囲む矩形が画面に収まっていることと、その中心が構図の中央にあることを確かめる。
fn 矩形を判定する(矩形: &囲む矩形, 幅: usize, 高さ: usize) -> Result<(), String> {
    let 矩形幅 = 矩形.x最大 - 矩形.x最小 + 1;
    let 矩形高さ = 矩形.y最大 - 矩形.y最小 + 1;
    for (名前, 辺, 全体) in [("横", 矩形幅, 幅), ("縦", 矩形高さ, 高さ)] {
        let 割合 = 割合を求める(u64::try_from(辺).unwrap_or(u64::MAX), 全体)?;
        if 割合 > 矩形の辺の上限 {
            return Err(format!("囲む矩形の{名前}が画面の{割合:.4}を占め、上限{矩形の辺の上限}を超えた"));
        }
    }
    for (名前, 中心の2倍, 全体) in [("横", 矩形.x最小 + 矩形.x最大, 幅), ("縦", 矩形.y最小 + 矩形.y最大, 高さ)] {
        let 中心割合 = 割合を求める(u64::try_from(中心の2倍).unwrap_or(u64::MAX), 全体 * 2)?;
        let ずれ = (中心割合 - 0.5).abs();
        if ずれ > 中心のずれの上限 {
            return Err(format!(
                "囲む矩形の{名前}の中心が画面中央から{ずれ:.4}ずれ、上限{中心のずれの上限}を超えた"
            ));
        }
    }
    Ok(())
}

fn 割合を求める(分子: u64, 分母: usize) -> Result<f64, String> {
    let 分母 = u32::try_from(分母).map_err(|誤り| format!("画素数を割合の分母へ写せない: {誤り}"))?;
    if 分母 == 0 {
        return Err("読み戻し画像の画素数が0である".to_string());
    }
    let 分子 = u32::try_from(分子).map_err(|誤り| format!("画素数を割合の分子へ写せない: {誤り}"))?;
    Ok(f64::from(分子) / f64::from(分母))
}
