//! 囲む矩形が画面のどこにどれだけ広がっているかの判定。受け取るのは矩形と読み戻し画像、返すのは合否である。
//! 何を数えて矩形を作るかは`object_pixels`が、絵として成立しているかの全体の判定は`judgment`が持つ。
//!
//! 向きを綴りでなく枝で持つのは、横の辺の割合を縦の全体で割る取り違えが、綴りの組では型を通ってしまうためである。

use super::object_pixels::囲む矩形;
use crate::acceptance::{判定の名前, 検収エラー, 画素の占める割合, 読み戻し画像};

/// 囲む矩形が画面の辺に対して占める割合の上限。これを超えると物体が画面から溢れており、境界箱の全体が写っていない。
const 矩形の辺の上限: f64 = 0.85;
/// 囲む矩形の中心が画面中央からずれてよい割合。カメラは物体の体積の中心を注視するため、構図の中央に来る。
const 中心のずれの上限: f64 = 0.12;

#[derive(Clone, Copy)]
enum 辺の向き {
    横,
    縦,
}

impl 辺の向き {
    fn 綴り(self) -> &'static str {
        match self {
            Self::横 => "横",
            Self::縦 => "縦",
        }
    }

    /// この向きでの、矩形の辺の長さと画面の辺の長さ。両方を1つの枝から取ることで、横の辺を縦の全体で割れなくする。
    fn 辺の長さと画面の長さ(self, 矩形: &囲む矩形, 画像: &読み戻し画像) -> (usize, usize) {
        match self {
            Self::横 => (矩形.x最大 - 矩形.x最小 + 1, 画像.幅().画素数()),
            Self::縦 => (矩形.y最大 - 矩形.y最小 + 1, 画像.高さ().画素数()),
        }
    }

    /// この向きでの、矩形の中心の2倍と画面の長さ。2倍のまま持つのは、中心が画素の半分に落ちる場合に丸めないためである。
    fn 中心の2倍と画面の長さ(self, 矩形: &囲む矩形, 画像: &読み戻し画像) -> (usize, usize) {
        match self {
            Self::横 => (矩形.x最小 + 矩形.x最大, 画像.幅().画素数()),
            Self::縦 => (矩形.y最小 + 矩形.y最大, 画像.高さ().画素数()),
        }
    }
}

pub(super) fn 画面の中での位置と広がりを判定する(矩形: &囲む矩形, 画像: &読み戻し画像) -> Result<(), 検収エラー> {
    for 向き in [辺の向き::横, 辺の向き::縦] {
        let (辺, 画面の長さ) = 向き.辺の長さと画面の長さ(矩形, 画像);
        let 割合 = 画素の占める割合::部分と全体から求める(辺, 画面の長さ)?;
        画面に占める割合の判定名(向き).上限を課す(割合.値(), 矩形の辺の上限)?;

        let (中心の2倍, 画面の長さ) = 向き.中心の2倍と画面の長さ(矩形, 画像);
        let 中心割合 = 画素の占める割合::部分と全体から求める(中心の2倍, 画面の長さ * 2)?;
        中心のずれの判定名(向き).上限を課す((中心割合.値() - 0.5).abs(), 中心のずれの上限)?;
    }
    Ok(())
}

fn 画面に占める割合の判定名(向き: 辺の向き) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("囲む矩形の{}が画面に占める割合", 向き.綴り()))
}

fn 中心のずれの判定名(向き: 辺の向き) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("囲む矩形の{}の中心が画面中央からずれた割合", 向き.綴り()))
}
