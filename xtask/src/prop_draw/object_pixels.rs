//! 背景でない画素の広がりを測る工程。受け取るのは画像と背景色、返すのは件数・囲む矩形・明度の範囲である。
//! 何を合格とみなすかは`judgment`が決め、ここは数えることだけを担う。

use super::background_color::同じ色か;
use crate::acceptance::{画素の横位置, 画素の縦位置, 読み戻し画像};

pub(super) struct 囲む矩形 {
    pub(super) x最小: usize,
    pub(super) x最大: usize,
    pub(super) y最小: usize,
    pub(super) y最大: usize,
}

/// 背景でない画素の分布。1つも無い場合を件数0で表すと、囲む矩形が意味を持たないまま消費側へ渡る。
pub(super) enum 物体画素の要約 {
    背景だけ,
    物体あり {
        件数: usize,
        矩形: 囲む矩形,
        明度最小: u8,
        明度最大: u8,
    },
}

pub(super) fn 要約する(画像: &読み戻し画像, 背景色: [u8; 3]) -> 物体画素の要約 {
    let mut 件数 = 0usize;
    let mut 矩形 = 囲む矩形 {
        x最小: 画像.幅().画素数(),
        x最大: 0,
        y最小: 画像.高さ().画素数(),
        y最大: 0,
    };
    let mut 明度最小 = u8::MAX;
    let mut 明度最大 = u8::MIN;
    for y in 0..画像.高さ().画素数() {
        for x in 0..画像.幅().画素数() {
            let 色 = 画像.座標の画素(画素の横位置::生成する(x), 画素の縦位置::生成する(y));
            if 同じ色か(色, 背景色) {
                continue;
            }
            件数 += 1;
            矩形.x最小 = 矩形.x最小.min(x);
            矩形.x最大 = 矩形.x最大.max(x);
            矩形.y最小 = 矩形.y最小.min(y);
            矩形.y最大 = 矩形.y最大.max(y);
            let 明度 = 明度を求める(色);
            明度最小 = 明度最小.min(明度);
            明度最大 = 明度最大.max(明度);
        }
    }
    if 件数 == 0 {
        return 物体画素の要約::背景だけ;
    }
    物体画素の要約::物体あり {
        件数,
        矩形,
        明度最小,
        明度最大,
    }
}

/// 面ごとの明るさの違いを比べるための1成分。緑を採るのは、白い方向光の下ではRGBのどれも同じ順序に並ぶうえ、
/// 緑が人の明るさの知覚へ最も寄与するためである。
fn 明度を求める(色: [u8; 3]) -> u8 {
    色[1]
}
