//! 破綻防止帯の閾値と上限の台帳。担当するのは「飽和と黒潰れをどの階調で数え、どの割合まで許すか」を1箇所に置くことだけであり、
//! どの画素を対象にするかも失敗の文面も、帯を使う検収の入口ごとに決める。
//!
//! 帯を広く取るのは、自動露出を入れない段だからである(参照: `_doc/設計/放射輝度問い合わせ階層.md`
//! 「3-Icの消費式と実装段割り」)。明るさの自然さはオーナーの目視に残し、機械条件は破綻の有無だけを見る。
//!
//! 値を入口ごとに持たないのは、遠方環境の検収世界も地形の世界も目視見本の世界も、同じ「間接照明で絵が壊れていないか」を
//! 見るためである。世界が違うだけで帯の意味は変わらない。

/// 飽和とみなす明度の下限。3成分すべてがこの値以上の画素を飽和と数える。
pub const 飽和の下限: u8 = 254;

/// 黒潰れとみなす明度の上限。3成分すべてがこの値以下の画素を黒潰れと数える。
pub const 黒潰れの上限: u8 = 2;

/// 判定領域に許す飽和画素の割合の上限。
pub const 飽和割合の上限: f64 = 0.02;

/// 判定領域に許す黒潰れ画素の割合の上限。影に入った面や粗い金属は暗く写るため、完全な黒でなければよいという広さに取る。
pub const 黒潰れ割合の上限: f64 = 0.20;

pub fn 割合にする(件数: u64, 画素数: u64) -> f64 {
    f64::from(u32::try_from(件数).unwrap_or(u32::MAX)) / f64::from(u32::try_from(画素数).unwrap_or(u32::MAX))
}
