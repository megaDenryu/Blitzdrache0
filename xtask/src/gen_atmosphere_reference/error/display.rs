//! 大気の期待値の焼き出しエラーを人が読む1文へ写すトレイト実装。枝ごとに、どの前提がどう破れたかを出す。
//! 実装を型の定義と分けるのは、外部トレイトの実装が型自身の持ち物とは別の軸であるためである。

use std::fmt;

use super::大気の期待値の焼き出しエラー;

impl fmt::Display for 大気の期待値の焼き出しエラー {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::固定したリビジョンと食い違う { 名前, 実測, 固定 } => write!(
                書き手,
                "{名前}のHEADは{実測}であり、焼き出しが固定している{固定}と違う。出自の表示が実際と食い違うため生成を止める"
            ),
            Self::作業コピーに未コミットの変更がある { 名前, 変更一覧 } => write!(
                書き手,
                "{名前}の作業コピーに未コミットの変更がある。\n{変更一覧}\nHEADが固定リビジョンのままでも焼くのは変更後のコードであり、生成物へ付く出自の表示が実際に焼いたコードと食い違うため生成を止める。変更を戻すか、コミットしたうえで固定リビジョンを更新すること"
            ),
            Self::作業コピーでgitを起こせなかった { 作業コピー, 誤り } => {
                write!(書き手, "{}でgitを起動できない: {誤り}", 作業コピー.display())
            }
            Self::作業コピーでgitが失敗して終わった {
                作業コピー, 引数の並び
            } => write!(
                書き手,
                "{}で`git {引数の並び}`が失敗した。gitの作業コピーであることと、部分モジュールが初期化済みであることを確かめること",
                作業コピー.display()
            ),
            Self::作業コピーの照合の標準出力がUTF8でない { 誤り } => write!(書き手, "gitの出力がUTF-8でない: {誤り}"),
            Self::参照実装の必要ファイルが無い { パス } => {
                write!(書き手, "{}が無い。作業コピーの取得と部分モジュールの初期化を確かめること", パス.display())
            }
            Self::出力先を作れなかった { パス, 誤り } => {
                write!(書き手, "{}を作れない: {誤り}", パス.display())
            }
            Self::現在のディレクトリを読めなかった { 誤り } => {
                write!(書き手, "現在のディレクトリを読めない: {誤り}")
            }
            Self::構築手順を起こせなかった { 構築手順, 誤り } => {
                write!(書き手, "{}を起動できない: {誤り}", 構築手順.display())
            }
            Self::構築手順が失敗して終わった { 構築手順 } => write!(
                書き手,
                "{}が失敗した。MSVCのC++ツールセットが導入されているか確かめること",
                構築手順.display()
            ),
            Self::焼き出しを起こせなかった { 実行ファイル, 誤り } => {
                write!(書き手, "{}を起動できない: {誤り}", 実行ファイル.display())
            }
            Self::焼き出しが異常終了した { 実行ファイル } => {
                write!(書き手, "{}が異常終了した", 実行ファイル.display())
            }
            Self::焼き出しの出力がUTF8でない { 誤り } => {
                write!(書き手, "焼き出しの出力がUTF-8でない: {誤り}")
            }
            Self::焼き出しが1行も出さなかった => write!(書き手, "焼き出しが1行も出さなかった"),
            Self::生成物を書けなかった { パス, 誤り } => {
                write!(書き手, "{}へ書けない: {誤り}", パス.display())
            }
        }
    }
}
