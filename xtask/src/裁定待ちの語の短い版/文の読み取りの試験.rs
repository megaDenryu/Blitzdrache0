//! 定義の最初の文の切り出しと、散文の中の区切られたドメインの宣言の読み取りの試験。

use super::区切られたドメインの表記::区切られたドメイン;
use super::定義の最初の文::定義の最初の文;

fn 宣言を読む(文: &str) -> Option<&'static str> {
    区切られたドメイン::宣言の文から読む(文).map(|ドメイン| ドメイン.表記())
}

#[test]
fn 最初の句点までを最初の文にする() {
    assert_eq!(定義の最初の文::定義から切り出す("甲とは、何かのことである。補足の文である。").文(), "甲とは、何かのことである。");
}

#[test]
fn 括弧とコードの囲みの中の句点では文を終えない() {
    let 定義 = "甲とは、乙(丙。丁)と「戊。」と`己。`を持つもののことである。補足";
    assert_eq!(定義の最初の文::定義から切り出す(定義).文(), "甲とは、乙(丙。丁)と「戊。」と`己。`を持つもののことである。");
    assert_eq!(定義の最初の文::定義から切り出す("甲とは、乙（丙。）のことである。").文(), "甲とは、乙（丙。）のことである。");
}

#[test]
fn 句点の無い定義は全体を最初の文にする() {
    assert_eq!(定義の最初の文::定義から切り出す("甲とは、何かのことである ").文(), "甲とは、何かのことである");
}

#[test]
fn 範囲の前置きと鉤括弧を許して区切られたドメインの宣言を読む() {
    assert_eq!(宣言を読む("この節の区切られたドメインはすべて「開発基盤」である。"), Some("開発基盤"));
    assert_eq!(宣言を読む("区切られたドメインはどれも開発基盤である"), Some("開発基盤"));
    assert_eq!(宣言を読む("区切られたドメインは、断りの無いものは「開発基盤」である。"), Some("開発基盤"));
    assert_eq!(宣言を読む("甲である。区切られたドメインはゲーム実行である。"), Some("ゲーム実行"));
}

#[test]
fn ドメインの名前を1つだけ述べない文は宣言として読まない() {
    assert_eq!(宣言を読む("区切られたドメインは表に書く。名前は型から付けたのである"), None);
    assert_eq!(宣言を読む("区切られたドメインは、表の各行の2列目に書いた。"), None);
    assert_eq!(宣言を読む("区切られたドメインは、Escaの語が「ゲーム実行」、仕組みの層の語が「共通」である"), None);
    assert_eq!(宣言を読む("区切られたドメインは「未知の領域」である"), None);
}
