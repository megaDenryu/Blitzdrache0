//! 裁定待ちの語の元の一覧の原文。原文を見出しの塊へ分け、塊を読み手へ順に渡して短い版を組む。

use std::path::PathBuf;

use super::元の一覧の読み手::元の一覧の読み手;
use super::原文の塊::節の塊;
use super::生成した結果::短い定義一覧を生成した結果;

/// 裁定待ちの語の元の一覧の原文と、それを読んだファイルのパス。パスは短い版の冒頭の断りに書く。
pub(crate) struct 元の一覧の本文 {
    パス: PathBuf,
    原文: String,
}

impl 元の一覧の本文 {
    pub(super) fn パスと原文から生成する(パス: PathBuf, 原文: String) -> Self {
        Self { パス, 原文 }
    }

    pub(crate) fn 短い版を組む(&self) -> 短い定義一覧を生成した結果 {
        let mut 読み手 = 元の一覧の読み手::冒頭から始める(&self.パス);
        for 塊 in 節の塊::原文を分ける(&self.原文) {
            読み手.塊を読む(&塊);
        }
        読み手.読み終える()
    }
}
