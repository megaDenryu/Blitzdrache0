//! 元の一覧のうち、短い版の語として読めなかった行と、その理由。生成のコマンドは失敗として、古さの検査は違反として報告する。

use std::fmt;

pub(crate) struct 読めなかった行 {
    行番号: usize,
    理由: 読めなかった理由,
}

pub(super) enum 読めなかった理由 {
    表の見出しに語と暫定の定義の列が無い,
    見出しを読めなかった表の行である,
    表の見出しの次の行が区切りの行でない,
    縦棒で始まり縦棒で終わる形でない,
    表の行の列の数が見出しと違う { 行の列数: usize, 見出しの列数: usize },
    表の行の語か暫定の定義が空である,
    表の行の区切られたドメインが空である,
    語の見出しの暫定の定義の箇条が1つでない { 箇条の数: usize },
    語の見出しの箇条の値が空である,
    語の見出しの区切られたドメインの箇条が2つ以上ある,
    語の見出しの中に表がある,
}

impl 読めなかった行 {
    pub(super) fn 生成する(行番号: usize, 理由: 読めなかった理由) -> Self {
        Self { 行番号, 理由 }
    }

    pub(crate) fn 行番号(&self) -> usize {
        self.行番号
    }

    pub(crate) fn 理由の説明(&self) -> String {
        match &self.理由 {
            読めなかった理由::表の見出しに語と暫定の定義の列が無い => "表の見出しに「語」と「暫定の定義」の列が無い".to_string(),
            読めなかった理由::見出しを読めなかった表の行である => "見出しを読めなかった表の行である".to_string(),
            読めなかった理由::表の見出しの次の行が区切りの行でない => "表の見出しの次の行が区切りの行(|---|)でない".to_string(),
            読めなかった理由::縦棒で始まり縦棒で終わる形でない => "表の行が縦棒で始まり縦棒で終わる形でない".to_string(),
            読めなかった理由::表の行の列の数が見出しと違う { 行の列数, 見出しの列数 } => format!("表の行の列の数({行の列数})が見出しの列の数({見出しの列数})と違う"),
            読めなかった理由::表の行の語か暫定の定義が空である => "表の行の語か暫定の定義が空である".to_string(),
            読めなかった理由::表の行の区切られたドメインが空である => "表の行の区切られたドメインが空である".to_string(),
            読めなかった理由::語の見出しの暫定の定義の箇条が1つでない { 箇条の数 } => format!("語の見出しの「- **暫定の定義**:」の箇条が1つでない({箇条の数}個)"),
            読めなかった理由::語の見出しの箇条の値が空である => "語の見出しの暫定の定義か区切られたドメインの箇条の値が空である".to_string(),
            読めなかった理由::語の見出しの区切られたドメインの箇条が2つ以上ある => "語の見出しの「- **区切られたドメイン**:」の箇条が2つ以上ある".to_string(),
            読めなかった理由::語の見出しの中に表がある => "語の見出し(箇条書きの項目)の中に表がある".to_string(),
        }
    }
}

impl fmt::Display for 読めなかった行 {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}行目: {}", self.行番号, self.理由の説明())
    }
}
