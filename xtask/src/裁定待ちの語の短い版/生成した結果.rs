//! 裁定待ちの用語集から、語・分野・定義文の最初の文を抜き出して生成した一覧と、読み取りの結果を持つ。
//! 生成処理は、読み取れなかった行が無く、元の用語集で読んだ語数と生成した一覧の語数が一致する場合だけ、一覧をファイルへ保存できる。

use std::fmt;

use super::短い版の組み立て::短い版の本文;
use super::読めなかった行::読めなかった行;

pub(crate) struct 短い定義一覧を生成した結果 {
    短い版: 短い版の本文,
    読んだ語の数: usize,
    読めなかった行一覧: Vec<読めなかった行>,
}

/// 生成した定義一覧を保存できない理由。元の用語集を読み取れなかった行があるか、生成前後の語数が一致しない場合を表す。
pub(crate) enum 短い定義一覧を書けない理由<'a> {
    読めない行がある(&'a [読めなかった行]),
    語の数が合わない { 読んだ語の数: usize, 短い版の語の数: usize },
}

impl 短い定義一覧を生成した結果 {
    pub(super) fn 生成する(短い版: 短い版の本文, 読んだ語の数: usize, 読めなかった行一覧: Vec<読めなかった行>) -> Self {
        Self {
            短い版, 読んだ語の数, 読めなかった行一覧
        }
    }

    pub(crate) fn 短い版(&self) -> &短い版の本文 {
        &self.短い版
    }

    pub(crate) fn 読んだ語の数(&self) -> usize {
        self.読んだ語の数
    }

    pub(crate) fn 短い版を書いてよいかを確かめる(&self) -> Result<(), 短い定義一覧を書けない理由<'_>> {
        if !self.読めなかった行一覧.is_empty() {
            return Err(短い定義一覧を書けない理由::読めない行がある(&self.読めなかった行一覧));
        }
        let 短い版の語の数 = self.短い版.語の数を数える();
        if 短い版の語の数 != self.読んだ語の数 {
            return Err(短い定義一覧を書けない理由::語の数が合わない {
                読んだ語の数: self.読んだ語の数,
                短い版の語の数,
            });
        }
        Ok(())
    }
}

impl fmt::Display for 短い定義一覧を書けない理由<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::読めない行がある(読めなかった行一覧) => {
                writeln!(f, "元の一覧に読めない行が{}件ある", 読めなかった行一覧.len())?;
                読めなかった行一覧.iter().try_for_each(|行| writeln!(f, "  {行}"))
            }
            Self::語の数が合わない { 読んだ語の数, 短い版の語の数 } => write!(f, "読んだ語の数({読んだ語の数})と短い版の語の行の数({短い版の語の数})が合わない"),
        }
    }
}
