//! 元の一覧の「書き方」と「裁定の記録」の節(語を載せない節)。短い版の生成は、この節とその下の節を読まない。
//! 「書き方」の節が箇条書きの項目の見本を持つため、読まない節を見出しの名前で決める。

use super::原文の塊::見出しの行;

const 語を載せない節の名前一覧: [&str; 2] = ["書き方", "裁定の記録"];

#[derive(Clone, Copy)]
pub(super) struct 語を載せない節<'a> {
    見出し: 見出しの行<'a>,
}

impl<'a> 語を載せない節<'a> {
    /// 見出しの名前が語を載せない節の名前のどれかであれば、その見出しの節を返す。
    pub(super) fn 見出しから見分ける(見出し: 見出しの行<'a>) -> Option<Self> {
        語を載せない節の名前一覧.contains(&見出し.名前()).then_some(Self { 見出し })
    }

    /// 見出しがこの節の下の節の見出しか。この節の見出しより井桁が多ければ真を返す。
    pub(super) fn 見出しがこの節の中にあるか(&self, 見出し: &見出しの行<'_>) -> bool {
        見出し.井桁の数() > self.見出し.井桁の数()
    }
}
