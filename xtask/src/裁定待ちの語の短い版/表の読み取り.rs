//! 節の本文の表を1行ずつ読む状態。表の見出しで「語」「暫定の定義」「区切られたドメイン」の列の位置を見分け、次の行が区切りの行であることを確かめてから、
//! 残りの行を語として読む。表の外の行が来たら表を閉じる。見出しを読めなかった表は、その表の行を全部読めなかった行として返し、黙って飛ばさない。

use super::区切られたドメインの表記::区切られたドメイン;
use super::原文の塊::本文の行;
use super::裁定待ちの語::語の表記;
use super::読めなかった行::読めなかった理由;

pub(super) struct 表の読み取り {
    状態: 表の読み取りの状態,
}

#[derive(Clone, Copy)]
enum 表の読み取りの状態 {
    表の外,
    区切りを待つ(表の列),
    行を読む(表の列),
    読めない表,
}

/// 表の見出しから見分けた列の位置。区切られたドメインの列は無い表もある。
#[derive(Clone, Copy)]
struct 表の列 {
    列の数: usize,
    語の列: usize,
    定義の列: usize,
    ドメインの列: Option<usize>,
}

pub(super) enum 表の行の読み取り<'a> {
    表の行でない,
    見出しか区切りを読んだ,
    語を読んだ(表の語<'a>),
    読めなかった(読めなかった理由),
}

/// 表の1行から読んだ語。区切られたドメインは、表がその列を持つときだけ持つ。
pub(super) struct 表の語<'a> {
    pub(super) 語: 語の表記<'a>,
    pub(super) 列のドメイン: Option<区切られたドメイン<'a>>,
    pub(super) 定義: &'a str,
}

impl 表の読み取り {
    pub(super) fn 表の外から始める() -> Self {
        Self {
            状態: 表の読み取りの状態::表の外
        }
    }

    pub(super) fn 行を読む<'a>(&mut self, 行: &本文の行<'a>) -> 表の行の読み取り<'a> {
        if !行.表の行か() {
            self.状態 = 表の読み取りの状態::表の外;
            return 表の行の読み取り::表の行でない;
        }
        let マス一覧 = マスに分ける(行.文字列());
        let (次の状態, 読み取り) = match self.状態 {
            表の読み取りの状態::表の外 => match マス一覧.as_deref().and_then(表の列::見出しから読む) {
                Some(列) => (表の読み取りの状態::区切りを待つ(列), 表の行の読み取り::見出しか区切りを読んだ),
                None => (表の読み取りの状態::読めない表, 表の行の読み取り::読めなかった(読めなかった理由::表の見出しに語と暫定の定義の列が無い)),
            },
            表の読み取りの状態::区切りを待つ(列) if マス一覧.as_deref().is_some_and(|マス| 列.区切りの行か(マス)) => (表の読み取りの状態::行を読む(列), 表の行の読み取り::見出しか区切りを読んだ),
            表の読み取りの状態::区切りを待つ(_) => (表の読み取りの状態::読めない表, 表の行の読み取り::読めなかった(読めなかった理由::表の見出しの次の行が区切りの行でない)),
            表の読み取りの状態::行を読む(列) => (表の読み取りの状態::行を読む(列), 列.語を読む(マス一覧.as_deref())),
            表の読み取りの状態::読めない表 => (表の読み取りの状態::読めない表, 表の行の読み取り::読めなかった(読めなかった理由::見出しを読めなかった表の行である)),
        };
        self.状態 = 次の状態;
        読み取り
    }
}

/// 行の前後の空白を除き、両端の縦棒の内側を縦棒で区切って、マスごとに前後の空白を除く。両端が縦棒でなければ `None` を返す。
fn マスに分ける(文字列: &str) -> Option<Vec<&str>> {
    let 内側 = 文字列.trim().strip_prefix('|')?.strip_suffix('|')?;
    Some(内側.split('|').map(str::trim).collect())
}

impl 表の列 {
    fn 見出しから読む(マス一覧: &[&str]) -> Option<Self> {
        let 位置 = |名前: &str| マス一覧.iter().position(|マス| *マス == 名前);
        Some(Self {
            列の数: マス一覧.len(),
            語の列: 位置("語")?,
            定義の列: 位置("暫定の定義")?,
            ドメインの列: 位置("区切られたドメイン"),
        })
    }

    fn 区切りの行か(&self, マス一覧: &[&str]) -> bool {
        マス一覧.len() == self.列の数 && マス一覧.iter().all(|マス| !マス.is_empty() && マス.chars().all(|文字| 文字 == '-' || 文字 == ':'))
    }

    fn 語を読む<'a>(&self, マス一覧: Option<&[&'a str]>) -> 表の行の読み取り<'a> {
        let Some(マス一覧) = マス一覧 else {
            return 表の行の読み取り::読めなかった(読めなかった理由::縦棒で始まり縦棒で終わる形でない);
        };
        if マス一覧.len() != self.列の数 {
            return 表の行の読み取り::読めなかった(読めなかった理由::表の行の列の数が見出しと違う {
                行の列数: マス一覧.len(),
                見出しの列数: self.列の数,
            });
        }
        let (Some(語), 定義) = (語の表記::空でなければ包む(マス一覧[self.語の列]), マス一覧[self.定義の列]) else {
            return 表の行の読み取り::読めなかった(読めなかった理由::表の行の語か暫定の定義が空である);
        };
        if 定義.is_empty() {
            return 表の行の読み取り::読めなかった(読めなかった理由::表の行の語か暫定の定義が空である);
        }
        let 列のドメイン = match self.ドメインの列.map(|列| 区切られたドメイン::空でなければ包む(マス一覧[列])) {
            None => None,
            Some(Some(ドメイン)) => Some(ドメイン),
            Some(None) => return 表の行の読み取り::読めなかった(読めなかった理由::表の行の区切られたドメインが空である),
        };
        表の行の読み取り::語を読んだ(表の語 { 語, 列のドメイン, 定義 })
    }
}
