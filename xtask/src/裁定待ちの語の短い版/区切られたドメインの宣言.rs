//! 散文か定義の中の「区切られたドメインは〜である」という文(区切られたドメインの宣言)と、その読み方。
//! 宣言として読むのは、区切られたドメインの8つの名前のどれか1つだけを述べた形(「すべて」「どれも」「、断りの無いものは」の前置きと鉤括弧は許す)である。
//! 「区切られたドメインは表に書く」のように名前を述べない文は宣言でない。参照: CLAUDE.md「区切られたドメイン」。

use super::区切られたドメインの表記::区切られたドメイン;

const 宣言の頭: &str = "区切られたドメインは";
const 範囲の前置き一覧: [&str; 3] = ["すべて", "どれも", "、断りの無いものは"];
const 宣言の結び: &str = "である";

#[derive(Clone, Copy)]
pub(super) struct 区切られたドメインの宣言 {
    述べた区切られたドメイン: 区切られたドメイン<'static>,
}

impl 区切られたドメインの宣言 {
    /// 文の中の最初の宣言を読む。宣言が無ければ `None` を返す。
    pub(super) fn 文の中の最初の宣言を読む(文: &str) -> Option<Self> {
        文.match_indices(宣言の頭).find_map(|(位置, _)| Self::宣言の頭より後を読む(&文[位置 + 宣言の頭.len()..]))
    }

    pub(super) fn 述べた区切られたドメイン(&self) -> 区切られたドメイン<'static> {
        self.述べた区切られたドメイン
    }

    /// 宣言の頭より後の文字列から、範囲の前置きを除き、鉤括弧の中か結びの前までを区切られたドメインの名前として読む。
    fn 宣言の頭より後を読む(頭より後: &str) -> Option<Self> {
        let 前置きより後 = 範囲の前置き一覧.iter().find_map(|前置き| 頭より後.strip_prefix(前置き)).unwrap_or(頭より後);
        let (名前, 名前より後) = match 前置きより後.strip_prefix('「') {
            Some(括弧の中から) => {
                let 閉じ = 括弧の中から.find('」')?;
                (&括弧の中から[..閉じ], &括弧の中から[閉じ + '」'.len_utf8()..])
            }
            None => {
                let 結び = 前置きより後.find(宣言の結び)?;
                (&前置きより後[..結び], &前置きより後[結び..])
            }
        };
        if !名前より後.starts_with(宣言の結び) {
            return None;
        }
        区切られたドメイン::既知の名前なら包む(名前).map(|述べた区切られたドメイン| Self { 述べた区切られたドメイン })
    }
}
