//! 元の一覧の形の違う節(箇条書きの項目・3列と4列と5列の表・語を載せない節)を短い版へ組む試験と、読めない行を報告する試験。

use std::path::PathBuf;

use super::元の一覧::元の一覧の本文;
use super::生成した結果::{短い定義一覧を書けない理由, 短い定義一覧を生成した結果};

fn 組む(原文: &str) -> 短い定義一覧を生成した結果 {
    元の一覧の本文::パスと原文から生成する(PathBuf::from("元の一覧"), 原文.to_string()).短い版を組む()
}

fn 語の行一覧(結果: &短い定義一覧を生成した結果) -> Vec<String> {
    結果.短い版().文字列().lines().filter(|行| 行.starts_with("- **")).map(str::to_string).collect()
}

fn 読めなかった行番号一覧(結果: &短い定義一覧を生成した結果) -> Vec<usize> {
    match 結果.短い版を書いてよいかを確かめる() {
        Err(短い定義一覧を書けない理由::読めない行がある(一覧)) => 一覧.iter().map(|行| 行.行番号()).collect(),
        _ => Vec::new(),
    }
}

#[test]
fn 箇条書きの項目は見出しを語にし箇条のドメインと定義文の最初の文を書く() {
    let 結果 = 組む("# 題\n## 語の節\n### 歩行方向\n\n- **区切られたドメイン**: ゲーム実行\n- **暫定の定義**: 歩行方向とは、歩く向きのことである。生成の口は1つである\n- **使っている場所**: どこか\n");
    assert_eq!(語の行一覧(&結果), vec!["- **歩行方向**(ゲーム実行): 歩行方向とは、歩く向きのことである。"]);
    assert!(結果.短い版().文字列().contains("## 語の節\n\n- **歩行方向**"), "項目の見出しでなく節の見出しを書く: {}", 結果.短い版().文字列());
}

#[test]
fn ドメインの列の無い表は節の散文の宣言を下の節へ受け継ぐ() {
    let 原文 = "## 層の語\n\n区切られたドメインはすべて「開発基盤」である。\n\n### モデルの層\n\n| 語 | 暫定の定義 | 使っている場所 |\n|---|---|---|\n| 命題 | 命題とは、真偽を問う式のことである。形は7つある | どこか |\n";
    assert_eq!(語の行一覧(&組む(原文)), vec!["- **命題**(開発基盤): 命題とは、真偽を問う式のことである。"]);
}

#[test]
fn 断りの無いものの既定より行の定義が述べる宣言を先に使う() {
    let 原文 = "## 役割の語\n\n区切られたドメインは、断りの無いものは「開発基盤」である。\n\n| 語 | 暫定の定義 | 使っている場所 | 既存語で表せないと考えた理由 |\n|---|---|---|---|\n| 甲 | 甲とは、役割のことである | 場所 | 理由 |\n| 乙 | 乙とは、口のことである。区切られたドメインはゲーム実行である | 場所 | 理由 |\n";
    assert_eq!(語の行一覧(&組む(原文)), vec!["- **甲**(開発基盤): 甲とは、役割のことである", "- **乙**(ゲーム実行): 乙とは、口のことである。"]);
}

#[test]
fn ドメインの列を持つ表は列の値を使い宣言の無い節ではドメインを空欄にする() {
    let 原文 = "## 列の有る節\n\n| 語 | 区切られたドメイン | 暫定の定義 | 使っている場所 | 旧名 |\n|---|---|---|---|---|\n| 丙 | 物理 | 丙とは、力のことである | 場所 | 旧 |\n\n## 列の無い節\n\n| 語 | 暫定の定義 | 使っている場所 |\n|---|---|---|\n| 丁 | 丁とは、何かのことである | 場所 |\n";
    assert_eq!(語の行一覧(&組む(原文)), vec!["- **丙**(物理): 丙とは、力のことである", "- **丁**: 丁とは、何かのことである"]);
}

#[test]
fn 語を載せない節と語の無い節の見出しは書かない() {
    let 結果 = 組む("## 書き方\n\n- **暫定の定義**: 「Xとは〜のことである」の形で書く\n\n## 散文だけの節\n\n説明の文である。\n\n## 裁定の記録\n\n| 語 | 暫定の定義 |\n|---|---|\n| 戊 | 戊とは、何かのことである |\n");
    assert!(語の行一覧(&結果).is_empty());
    assert!(!結果.短い版().文字列().contains("## "), "語の無い節の見出しを書いた: {}", 結果.短い版().文字列());
    assert!(結果.短い版を書いてよいかを確かめる().is_ok());
}

#[test]
fn 語を載せない節の下の節は読まず同じ深さの次の節からまた読む() {
    let 結果 = 組む("## 裁定の記録\n### 甲\n- **暫定の定義**: 甲とは、何かである\n#### 乙の節\n| 語 | 暫定の定義 |\n|---|---|\n| 乙 | 乙とは、何かである |\n## 丙の節\n### 丙\n- **暫定の定義**: 丙とは、何かである\n");
    assert_eq!(語の行一覧(&結果), vec!["- **丙**: 丙とは、何かである"]);
    assert!(結果.短い版を書いてよいかを確かめる().is_ok());
}

#[test]
fn 読めない表の行を行番号付きで報告し黙って飛ばさない() {
    let 原文 = "## 節\n\n| 名前 | 説明 |\n|---|---|\n| 甲 | 甲とは |\n\n| 語 | 暫定の定義 |\n| 乙 | 乙とは |\n\n| 語 | 暫定の定義 |\n|---|---|\n| 丙 | 丙とは、何かである | 余分 |\n| 丁 |  |\n| 戊 | 戊とは、何かである\n";
    assert_eq!(読めなかった行番号一覧(&組む(原文)), vec![3, 4, 5, 8, 12, 13, 14]);
}

#[test]
fn 箇条書きの項目の定義の箇条が2つあるかドメインの箇条が2つあれば読めない行として報告する() {
    let 原文 = "## 節\n### 甲\n- **暫定の定義**: 甲とは、何かである\n- **暫定の定義**: 重ねた定義である\n### 乙\n- **区切られたドメイン**: 物理\n- **区切られたドメイン**: 描画\n- **暫定の定義**: 乙とは、何かである\n";
    assert_eq!(読めなかった行番号一覧(&組む(原文)), vec![2, 5]);
}

#[test]
fn 読んだ語の数と短い版の語の行の数が一致する() {
    let 原文 = "## 節\n\n| 語 | 暫定の定義 |\n|---|---|\n| 甲 | 甲とは、何かである |\n| 乙 | 乙とは、何かである |\n\n### 丙\n- **暫定の定義**: 丙とは、何かである\n";
    let 結果 = 組む(原文);
    assert_eq!(結果.読んだ語の数(), 3);
    assert_eq!(結果.短い版().語の数を数える(), 3);
    assert!(結果.短い版を書いてよいかを確かめる().is_ok());
}
