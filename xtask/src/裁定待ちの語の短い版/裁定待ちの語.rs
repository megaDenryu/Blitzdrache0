//! 短い版の1行になる、裁定待ちの語の1件。語の表記と区切られたドメインと定義文の最初の文を持ち、短い版の行の書き方を持つ。

use super::区切られたドメインの表記::区切られたドメイン;
use super::定義文の最初の文::定義文の最初の文;

/// 元の一覧が語として書いた表記(表の「語」の列か、箇条書きの項目の見出し)。
#[derive(Clone, Copy)]
pub(super) struct 語の表記<'a>(&'a str);

impl<'a> 語の表記<'a> {
    /// 空の表記を拒む。空の語は短い版の行にできず、読めない行として報告するためである。
    pub(super) fn 空でなければ包む(表記: &'a str) -> Option<Self> {
        (!表記.is_empty()).then_some(Self(表記))
    }
}

pub(super) struct 裁定待ちの語<'a> {
    語: 語の表記<'a>,
    ドメイン: Option<区切られたドメイン<'a>>,
    定義文の最初の文: 定義文の最初の文<'a>,
}

impl<'a> 裁定待ちの語<'a> {
    pub(super) fn 生成する(語: 語の表記<'a>, ドメイン: Option<区切られたドメイン<'a>>, 定義文の最初の文: 定義文の最初の文<'a>) -> Self {
        Self { 語, ドメイン, 定義文の最初の文 }
    }

    /// 短い版の1行。ドメインが分からない語は括弧を書かない。
    pub(super) fn 短い版の行(&self) -> String {
        match self.ドメイン {
            Some(ドメイン) => format!("- **{}**({}): {}", self.語.0, ドメイン.表記(), self.定義文の最初の文.文()),
            None => format!("- **{}**: {}", self.語.0, self.定義文の最初の文.文()),
        }
    }
}
