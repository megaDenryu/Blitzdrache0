//! 裁定待ちの語が属する区切られたドメインの表記と、散文の中の「区切られたドメインは〜である」という宣言の読み方。
//! 宣言として読むのは、区切られたドメインの8つの名前のどれか1つだけを述べた形(「すべて」「どれも」「、断りの無いものは」の前置きと鉤括弧は許す)である。
//! 「区切られたドメインは表に書く」のように名前を述べない文は宣言でない。参照: CLAUDE.md「区切られたドメイン」。

const 区切られたドメインの名前一覧: [&str; 8] = ["共通", "描画", "物理", "ゲーム実行", "ECS", "資産ストリーミング", "エディター", "開発基盤"];
const 宣言の頭: &str = "区切られたドメインは";
const 範囲の前置き一覧: [&str; 3] = ["すべて", "どれも", "、断りの無いものは"];
const 宣言の結び: &str = "である";

#[derive(Clone, Copy)]
pub(super) struct 区切られたドメイン<'a>(&'a str);

impl<'a> 区切られたドメイン<'a> {
    /// 表の「区切られたドメイン」の列か箇条書きの値。空の表記を拒む。
    pub(super) fn 空でなければ包む(表記: &'a str) -> Option<Self> {
        (!表記.is_empty()).then_some(Self(表記))
    }

    pub(super) fn 表記(&self) -> &'a str {
        self.0
    }

    /// 文の中の最初の宣言を読む。宣言が無ければ `None` を返す。
    pub(super) fn 宣言の文から読む(文: &str) -> Option<区切られたドメイン<'static>> {
        文.match_indices(宣言の頭).find_map(|(位置, _)| 宣言の続きを読む(&文[位置 + 宣言の頭.len()..]))
    }
}

fn 宣言の続きを読む(続き: &str) -> Option<区切られたドメイン<'static>> {
    let 続き = 範囲の前置き一覧.iter().find_map(|前置き| 続き.strip_prefix(前置き)).unwrap_or(続き);
    let (名前, 結びより後) = match 続き.strip_prefix('「') {
        Some(括弧の中から) => {
            let 閉じ = 括弧の中から.find('」')?;
            (&括弧の中から[..閉じ], &括弧の中から[閉じ + '」'.len_utf8()..])
        }
        None => {
            let 結び = 続き.find(宣言の結び)?;
            (&続き[..結び], &続き[結び..])
        }
    };
    if !結びより後.starts_with(宣言の結び) {
        return None;
    }
    区切られたドメインの名前一覧.iter().find(|既知の名前| **既知の名前 == 名前).map(|既知の名前| 区切られたドメイン(*既知の名前))
}
