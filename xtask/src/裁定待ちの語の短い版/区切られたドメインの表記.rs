//! 裁定待ちの語が属する区切られたドメインの表記。表の列か箇条書きが書いた値と、区切られたドメインの宣言が述べた8つの名前のどれかを包む。
//! 宣言の読み方は `xtask/src/裁定待ちの語の短い版/区切られたドメインの宣言.rs` にある。参照: CLAUDE.md「区切られたドメイン」。

const 区切られたドメインの名前一覧: [&str; 8] = ["共通", "描画", "物理", "ゲーム実行", "ECS", "資産ストリーミング", "エディター", "開発基盤"];

#[derive(Clone, Copy)]
pub(super) struct 区切られたドメイン<'a>(&'a str);

impl<'a> 区切られたドメイン<'a> {
    /// 表の「区切られたドメイン」の列か箇条書きの値。空の表記を拒む。
    pub(super) fn 空でなければ包む(表記: &'a str) -> Option<Self> {
        (!表記.is_empty()).then_some(Self(表記))
    }

    pub(super) fn 表記(&self) -> &'a str {
        self.0
    }
}

impl 区切られたドメイン<'static> {
    /// 区切られたドメインの8つの名前のどれかと等しければ包む。それ以外の名前は `None` を返す。
    pub(super) fn 既知の名前なら包む(名前: &str) -> Option<Self> {
        区切られたドメインの名前一覧.iter().find(|既知の名前| **既知の名前 == 名前).map(|既知の名前| Self(既知の名前))
    }
}
