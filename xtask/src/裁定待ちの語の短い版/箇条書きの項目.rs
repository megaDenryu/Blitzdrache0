//! 元の一覧のうち、見出しを語とし、`- **暫定の定義**:` などの箇条書きで定義を書いた1件(箇条書きの項目)と、見出しの塊から箇条書きの項目を読む読み方。
//! 箇条書きの項目として読むのは、2個以上の井桁の見出しで、本文に暫定の定義の箇条を持つ塊である。
//! 暫定の定義の箇条はちょうど1つ、区切られたドメインの箇条は無いか1つでなければならず、本文に表を持ってはならない。

use super::区切られたドメインの表記::区切られたドメイン;
use super::原文の塊::節の塊;
use super::定義文の最初の文::定義文の最初の文;
use super::裁定待ちの語::{裁定待ちの語, 語の表記};
use super::読めなかった行::読めなかった理由;

const 定義の箇条の前置き: &str = "- **暫定の定義**:";
const ドメインの箇条の前置き: &str = "- **区切られたドメイン**:";

pub(super) struct 箇条書きの項目<'a> {
    語: 語の表記<'a>,
    定義: &'a str,
    箇条のドメイン: Option<区切られたドメイン<'a>>,
}

pub(super) enum 箇条書きの項目の読み取り<'a> {
    箇条書きの項目でない,
    読んだ(箇条書きの項目<'a>),
    読めなかった(読めなかった理由),
}

impl<'a> 箇条書きの項目<'a> {
    /// 見出しの塊を箇条書きの項目として読む。見出しが無いか、井桁が1個か、暫定の定義の箇条が無ければ、箇条書きの項目でないと答える。
    pub(super) fn 塊から読む(塊: &節の塊<'a>) -> 箇条書きの項目の読み取り<'a> {
        let 定義一覧 = 塊.箇条の値一覧(定義の箇条の前置き);
        let Some(見出し) = 塊.見出し().filter(|見出し| 見出し.井桁の数() >= 2 && !定義一覧.is_empty()) else {
            return 箇条書きの項目の読み取り::箇条書きの項目でない;
        };
        let ドメイン一覧 = 塊.箇条の値一覧(ドメインの箇条の前置き);
        let 理由 = match (定義一覧.as_slice(), ドメイン一覧.as_slice()) {
            _ if 塊.本文().iter().any(|行| 行.表の行か()) => 読めなかった理由::語の見出しの中に表がある,
            ([""], _) | ([_], [""]) => 読めなかった理由::語の見出しの箇条の値が空である,
            ([定義], [] | [_]) => match 語の表記::空でなければ包む(見出し.名前()) {
                Some(語) => {
                    let 箇条のドメイン = ドメイン一覧.first().copied().and_then(区切られたドメイン::空でなければ包む);
                    return 箇条書きの項目の読み取り::読んだ(Self { 語, 定義: *定義, 箇条のドメイン });
                }
                None => 読めなかった理由::語の見出しの箇条の値が空である,
            },
            ([_], _) => 読めなかった理由::語の見出しの区切られたドメインの箇条が2つ以上ある,
            (ほかの数の定義, _) => 読めなかった理由::語の見出しの暫定の定義の箇条が1つでない { 箇条の数: ほかの数の定義.len() },
        };
        箇条書きの項目の読み取り::読めなかった(理由)
    }

    /// 短い版へ書く裁定待ちの語にする。区切られたドメインは、箇条が書いたものを、無ければ項目を囲む節の散文が宣言したものを使う。
    pub(super) fn 裁定待ちの語にする(&self, 節の散文のドメイン: Option<区切られたドメイン<'a>>) -> 裁定待ちの語<'a> {
        裁定待ちの語::生成する(self.語, self.箇条のドメイン.or(節の散文のドメイン), 定義文の最初の文::定義から切り出す(self.定義))
    }
}
