//! 元の一覧の表の1行から読んだ語(表の語)と、それを短い版へ書く裁定待ちの語にする直し方。
//! 箇条書きで定義を書いた1件(`xtask/src/裁定待ちの語の短い版/箇条書きの項目.rs`)と並ぶ、もう1つの語の書き方である。

use super::マス::マス;
use super::区切られたドメインの宣言::区切られたドメインの宣言;
use super::区切られたドメインの表記::区切られたドメイン;
use super::定義文の最初の文::定義文の最初の文;
use super::裁定待ちの語::{裁定待ちの語, 語の表記};

/// 表の1行から読んだ語。区切られたドメインは、表がその列を持つときだけ持つ。
pub(super) struct 表の語<'a> {
    語: 語の表記<'a>,
    列のドメイン: Option<区切られたドメイン<'a>>,
    定義: マス<'a>,
}

impl<'a> 表の語<'a> {
    pub(super) const fn 生成する(語: 語の表記<'a>, 列のドメイン: Option<区切られたドメイン<'a>>, 定義: マス<'a>) -> Self {
        Self { 語, 列のドメイン, 定義 }
    }

    /// 短い版へ書く裁定待ちの語にする。区切られたドメインは、表の列が書いたものを、無ければ定義が述べる宣言を、それも無ければ表を囲む節の散文が宣言したものを使う。
    pub(super) fn 裁定待ちの語にする(&self, 節の散文のドメイン: Option<区切られたドメイン<'a>>) -> 裁定待ちの語<'a> {
        let ドメイン = self
            .列のドメイン
            .or_else(|| 区切られたドメインの宣言::文の中の最初の宣言を読む(self.定義.値()).map(|宣言| 宣言.述べた区切られたドメイン()))
            .or(節の散文のドメイン);
        裁定待ちの語::生成する(self.語, ドメイン, 定義文の最初の文::定義から切り出す(self.定義.値()))
    }
}
