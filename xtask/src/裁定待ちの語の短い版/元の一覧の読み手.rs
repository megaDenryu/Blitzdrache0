//! 元の一覧の原文の塊を1つずつ読み、短い版を組み立てる読み手。開いている見出しを積み重ねで持ち、語を書く直前に、まだ書いていない見出しを書く。
//!
//! 見出しの塊は3通りに読む。「書き方」「裁定の記録」の節とその下は語を載せない節であり、読まない。
//! 2個以上の井桁の見出しで、本文に `- **暫定の定義**:` の箇条を持つものは、見出しを語とする箇条書きの項目である。それ以外は節であり、本文の表を読む。
//! 語の区切られたドメインは、表の列か箇条が書いたものを使う。書いていなければ、表の行の定義が述べる宣言、開いている節の散文が述べる宣言(内側の節から探す)の順に探し、
//! どれも無ければ空欄にする。宣言の読み方は `xtask/src/裁定待ちの語の短い版/区切られたドメインの表記.rs` にある。

use std::path::Path;

use super::区切られたドメインの表記::区切られたドメイン;
use super::原文の塊::{節の塊, 見出しの行};
use super::定義文の最初の文::定義文の最初の文;
use super::短い版の組み立て::短い版の組み立て;
use super::生成した結果::短い定義一覧を生成した結果;
use super::表の読み取り::{表の行の読み取り, 表の読み取り};
use super::裁定待ちの語::{裁定待ちの語, 語の表記};
use super::読めなかった行::{読めなかった理由, 読めなかった行};

const 語を載せない節の名前一覧: [&str; 2] = ["書き方", "裁定の記録"];
const 定義の箇条の前置き: &str = "- **暫定の定義**:";
const ドメインの箇条の前置き: &str = "- **区切られたドメイン**:";

struct 開いている節<'a> {
    見出し: 見出しの行<'a>,
    散文のドメイン: Option<区切られたドメイン<'static>>,
    語を載せない節か: bool,
    書いたか: bool,
}

pub(super) struct 元の一覧の読み手<'a> {
    開いている節一覧: Vec<開いている節<'a>>,
    組み立て: 短い版の組み立て,
    読めなかった行一覧: Vec<読めなかった行>,
    読んだ語の数: usize,
}

impl<'a> 元の一覧の読み手<'a> {
    pub(super) fn 冒頭から始める(元の一覧のパス: &Path) -> Self {
        Self {
            開いている節一覧: Vec::new(),
            組み立て: 短い版の組み立て::冒頭から始める(元の一覧のパス),
            読めなかった行一覧: Vec::new(),
            読んだ語の数: 0,
        }
    }

    pub(super) fn 読み終える(self) -> 短い定義一覧を生成した結果 {
        短い定義一覧を生成した結果::生成する(self.組み立て.仕上げる(), self.読んだ語の数, self.読めなかった行一覧)
    }

    pub(super) fn 塊を読む(&mut self, 塊: &節の塊<'a>) {
        if let Some(見出し) = 塊.見出し() {
            self.開いている節一覧.retain(|節| 節.見出し.井桁の数() < 見出し.井桁の数());
            let 語を載せない節か = 語を載せない節の名前一覧.contains(&見出し.名前()) || self.開いている節一覧.iter().any(|節| 節.語を載せない節か);
            if !語を載せない節か && 見出し.井桁の数() >= 2 && !塊.箇条の値一覧(定義の箇条の前置き).is_empty() {
                self.箇条書きの項目を読む(見出し, 塊);
                return;
            }
            let 散文のドメイン = 塊.本文().iter().filter(|行| !行.表の行か()).find_map(|行| 区切られたドメイン::宣言の文から読む(行.文字列()));
            self.開いている節一覧.push(開いている節 {
                見出し,
                散文のドメイン,
                語を載せない節か,
                書いたか: false,
            });
            if 語を載せない節か {
                return;
            }
        }
        let mut 表 = 表の読み取り::表の外から始める();
        for 行 in 塊.本文() {
            match 表.行を読む(行) {
                表の行の読み取り::表の行でない | 表の行の読み取り::見出しか区切りを読んだ => {}
                表の行の読み取り::読めなかった(理由) => self.読めなかった行一覧.push(読めなかった行::生成する(行.行番号(), 理由)),
                表の行の読み取り::語を読んだ(表の語) => {
                    let ドメイン = 表の語.列のドメイン.or_else(|| 区切られたドメイン::宣言の文から読む(表の語.定義)).or_else(|| self.散文のドメイン());
                    self.語を書く(裁定待ちの語::生成する(表の語.語, ドメイン, 定義文の最初の文::定義から切り出す(表の語.定義)));
                }
            }
        }
    }

    fn 箇条書きの項目を読む(&mut self, 見出し: 見出しの行<'a>, 塊: &節の塊<'a>) {
        let 定義一覧 = 塊.箇条の値一覧(定義の箇条の前置き);
        let ドメイン一覧 = 塊.箇条の値一覧(ドメインの箇条の前置き);
        let 理由 = match (定義一覧.as_slice(), ドメイン一覧.as_slice()) {
            _ if 塊.本文().iter().any(|行| 行.表の行か()) => 読めなかった理由::語の見出しの中に表がある,
            ([""], _) => 読めなかった理由::語の見出しの箇条の値が空である,
            ([_], [""]) => 読めなかった理由::語の見出しの箇条の値が空である,
            ([定義], [] | [_]) => {
                let 語 = 語の表記::空でなければ包む(見出し.名前());
                let ドメイン = ドメイン一覧.first().copied().and_then(区切られたドメイン::空でなければ包む).or_else(|| self.散文のドメイン());
                if let Some(語) = 語 {
                    self.語を書く(裁定待ちの語::生成する(語, ドメイン, 定義文の最初の文::定義から切り出す(定義)));
                    return;
                }
                読めなかった理由::語の見出しの箇条の値が空である
            }
            ([_], _) => 読めなかった理由::語の見出しの区切られたドメインの箇条が2つ以上ある,
            (ほかの数の定義, _) => 読めなかった理由::語の見出しの暫定の定義の箇条が1つでない { 箇条の数: ほかの数の定義.len() },
        };
        self.読めなかった行一覧.push(読めなかった行::生成する(見出し.行番号(), 理由));
    }

    fn 散文のドメイン(&self) -> Option<区切られたドメイン<'static>> {
        self.開いている節一覧.iter().rev().find_map(|節| 節.散文のドメイン)
    }

    fn 語を書く(&mut self, 語: 裁定待ちの語<'_>) {
        for 節 in self.開いている節一覧.iter_mut().filter(|節| 節.見出し.井桁の数() >= 2 && !節.書いたか) {
            self.組み立て.見出しを書く(節.見出し.井桁の数(), 節.見出し.名前());
            節.書いたか = true;
        }
        self.組み立て.語を書く(&語);
        self.読んだ語の数 += 1;
    }
}
