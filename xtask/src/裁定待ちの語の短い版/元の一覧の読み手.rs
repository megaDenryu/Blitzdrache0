//! 元の一覧の原文の塊を1つずつ読み、短い版を組み立てる読み手。開いている見出しを積み重ねで持ち、語を書く直前に、まだ書いていない見出しを書く。
//!
//! 見出しの塊は3通りに読む。語を載せない節(`xtask/src/裁定待ちの語の短い版/語を載せない節.rs`)とその下は読まない。
//! 箇条書きの項目(`xtask/src/裁定待ちの語の短い版/箇条書きの項目.rs`)は、その項目を1つの語として書く。それ以外は節であり、本文の表を読む。
//! 語の区切られたドメインは、表の列か箇条が書いたものを使う。書いていなければ、表の行の定義が述べる宣言、開いている節の散文が述べる宣言(内側の節から探す)の順に探し、
//! どれも無ければ空欄にする。宣言の読み方は `xtask/src/裁定待ちの語の短い版/区切られたドメインの宣言.rs` にある。

use std::path::Path;

use super::区切られたドメインの宣言::区切られたドメインの宣言;
use super::区切られたドメインの表記::区切られたドメイン;
use super::原文の塊::{節の塊, 見出しの行};
use super::生成した結果::短い定義一覧を生成した結果;
use super::短い版の組み立て::短い版の組み立て;
use super::箇条書きの項目::{箇条書きの項目, 箇条書きの項目の読み取り};
use super::表の読み取り::{表の行の読み取り, 表の読み取り};
use super::裁定待ちの語::裁定待ちの語;
use super::語を載せない節::語を載せない節;
use super::読めなかった行::読めなかった行;

struct 開いている節<'a> {
    見出し: 見出しの行<'a>,
    散文のドメイン: Option<区切られたドメイン<'static>>,
    書いたか: bool,
}

pub(super) struct 元の一覧の読み手<'a> {
    開いている節一覧: Vec<開いている節<'a>>,
    開いている語を載せない節: Option<語を載せない節<'a>>,
    組み立て: 短い版の組み立て,
    読めなかった行一覧: Vec<読めなかった行>,
    読んだ語の数: usize,
}

impl<'a> 元の一覧の読み手<'a> {
    pub(super) fn 冒頭から始める(元の一覧のパス: &Path) -> Self {
        Self {
            開いている節一覧: Vec::new(),
            開いている語を載せない節: None,
            組み立て: 短い版の組み立て::冒頭から始める(元の一覧のパス),
            読めなかった行一覧: Vec::new(),
            読んだ語の数: 0,
        }
    }

    pub(super) fn 読み終える(self) -> 短い定義一覧を生成した結果 {
        短い定義一覧を生成した結果::生成する(self.組み立て.仕上げる(), self.読んだ語の数, self.読めなかった行一覧)
    }

    pub(super) fn 塊を読む(&mut self, 塊: &節の塊<'a>) {
        match 塊.見出し() {
            Some(見出し) => self.見出しの塊を読む(見出し, 塊),
            None => self.本文の表を読む(塊),
        }
    }

    fn 見出しの塊を読む(&mut self, 見出し: 見出しの行<'a>, 塊: &節の塊<'a>) {
        if self.開いている語を載せない節.is_some_and(|節| 節.見出しがこの節の中にあるか(&見出し)) {
            return;
        }
        self.開いている語を載せない節 = 語を載せない節::見出しから見分ける(見出し);
        self.開いている節一覧.retain(|節| 節.見出し.井桁の数() < 見出し.井桁の数());
        if self.開いている語を載せない節.is_some() {
            return;
        }
        match 箇条書きの項目::塊から読む(塊) {
            箇条書きの項目の読み取り::読んだ(項目) => self.語を書く(項目.裁定待ちの語にする(self.散文のドメイン())),
            箇条書きの項目の読み取り::読めなかった(理由) => self.読めなかった行一覧.push(読めなかった行::生成する(見出し.行番号(), 理由)),
            箇条書きの項目の読み取り::箇条書きの項目でない => self.節を開いて本文の表を読む(見出し, 塊),
        }
    }

    fn 節を開いて本文の表を読む(&mut self, 見出し: 見出しの行<'a>, 塊: &節の塊<'a>) {
        let 散文の宣言 = 塊.本文().iter().filter(|行| !行.表の行か()).find_map(|行| 区切られたドメインの宣言::文の中の最初の宣言を読む(行.文字列()));
        self.開いている節一覧.push(開いている節 {
            見出し,
            散文のドメイン: 散文の宣言.map(|宣言| 宣言.述べた区切られたドメイン()),
            書いたか: false,
        });
        self.本文の表を読む(塊);
    }

    fn 本文の表を読む(&mut self, 塊: &節の塊<'a>) {
        let mut 表 = 表の読み取り::表の外から始める();
        for 行 in 塊.本文() {
            match 表.行を読む(行) {
                表の行の読み取り::表の行でない | 表の行の読み取り::見出しか区切りを読んだ => {}
                表の行の読み取り::読めなかった(理由) => self.読めなかった行一覧.push(読めなかった行::生成する(行.行番号(), 理由)),
                表の行の読み取り::語を読んだ(表の語) => self.語を書く(表の語.裁定待ちの語にする(self.散文のドメイン())),
            }
        }
    }

    fn 散文のドメイン(&self) -> Option<区切られたドメイン<'static>> {
        self.開いている節一覧.iter().rev().find_map(|節| 節.散文のドメイン)
    }

    fn 語を書く(&mut self, 語: 裁定待ちの語<'_>) {
        for 節 in self.開いている節一覧.iter_mut().filter(|節| 節.見出し.井桁の数() >= 2 && !節.書いたか) {
            self.組み立て.見出しを書く(節.見出し.井桁の数(), 節.見出し.名前());
            節.書いたか = true;
        }
        self.組み立て.語を書く(&語);
        self.読んだ語の数 += 1;
    }
}
