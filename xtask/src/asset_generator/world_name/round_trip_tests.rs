//! 世界名の選択肢と一覧が食い違っていないことの回帰検査。呼ばれるのは`cargo test`だけである。
//!
//! 選択肢の脱落そのものは表が構文として塞いでいる。ここが固定するのは、表から生まれた4つ(選択肢・文字列・一覧・逆引き)が
//! 互いに整合していることである。同じ文字列を2つの行へ書いた場合など、表の書き方の誤りをここが拾う。

#![allow(clippy::unwrap_used)]

use super::世界名;

#[test]
fn 一覧が同じ選択肢を2度持たない() {
    let 一覧 = 世界名::一覧();
    let mut 文字列一覧: Vec<&str> = 一覧.iter().map(|世界| 世界.文字列()).collect();
    文字列一覧.sort_unstable();
    let 重複前の件数 = 文字列一覧.len();
    文字列一覧.dedup();
    assert_eq!(文字列一覧.len(), 重複前の件数, "一覧の中に同じ文字列の世界が2つある(表の2行が同じ文字列を持っている)");
}

/// 表の行から生まれた文字列と逆引きが対応していることを確かめる。同じ文字列を2行へ書くとここが落ちる。
#[test]
fn 文字列から解釈すると元の選択肢へ戻る() {
    assert!(世界名::一覧().len() >= 2, "一覧が選択肢を1つしか持たない");
    for 世界 in 世界名::一覧() {
        let 戻り = 世界名::引数の文字列から解釈する(世界.文字列());
        assert_eq!(戻り, Some(世界), "{}の文字列が元の選択肢へ戻らない", 世界.文字列());
    }
}

#[test]
fn 知らない文字列は無しになる() {
    assert_eq!(世界名::引数の文字列から解釈する("unknown_world"), None);
    assert_eq!(世界名::引数の文字列から解釈する(""), None);
}
