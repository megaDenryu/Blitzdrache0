//! 世界名の枝と一覧が食い違っていないことの回帰検査。呼ばれるのは`cargo test`だけである。
//!
//! 枝の脱落そのものは表が構文として塞いでいる。ここが固定するのは、表から生まれた4つ(枝・綴り・一覧・逆引き)が
//! 互いに整合していることである。同じ綴りを2つの行へ書いた場合など、表の書き方の誤りをここが拾う。

#![allow(clippy::unwrap_used)]

use super::世界名;

#[test]
fn 一覧が同じ枝を2度持たない() {
    let 一覧 = 世界名::一覧();
    let mut 綴り一覧: Vec<&str> = 一覧.iter().map(|世界| 世界.綴り()).collect();
    綴り一覧.sort_unstable();
    let 重複前の件数 = 綴り一覧.len();
    綴り一覧.dedup();
    assert_eq!(
        綴り一覧.len(),
        重複前の件数,
        "一覧の中に同じ綴りの世界が2つある(表の2行が同じ綴りを持っている)"
    );
}

/// 表の行から生まれた綴りと逆引きが対応していることを確かめる。同じ綴りを2行へ書くとここが落ちる。
#[test]
fn 綴りから解釈すると元の枝へ戻る() {
    assert!(世界名::一覧().len() >= 2, "一覧が枝を1つしか持たない");
    for 世界 in 世界名::一覧() {
        let 戻り = 世界名::引数の綴りから解釈する(世界.綴り());
        assert_eq!(戻り, Some(世界), "{}の綴りが元の枝へ戻らない", 世界.綴り());
    }
}

#[test]
fn 知らない綴りは無しになる() {
    assert_eq!(世界名::引数の綴りから解釈する("unknown_world"), None);
    assert_eq!(世界名::引数の綴りから解釈する(""), None);
}
