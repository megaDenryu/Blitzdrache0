//! 部品の作業の入口だけが使う、ファイルの並びの引数列を組み立てる。
//!
//! カタログの組み上げも組み立ての突き合わせも「部品のglbの並びを渡す」形が同じであり、
//! 突き合わせはその手前に正解表のパスを1つ置くだけである。同じ並べ方を2箇所へ書かないため、ここが1つ持つ。

use std::path::Path;

use super::word_list::語の並び;
use crate::asset_generator::inspection_files::検査するファイル一覧;

pub(super) fn 部品のファイルの並びを足す(並び: &mut 語の並び, ファイル一覧: &検査するファイル一覧) {
    for ファイル in ファイル一覧.一覧() {
        並び.パスを足す(ファイル);
    }
}

/// 正解表のパスを先頭へ置いてから部品の並びを足す。突き合わせ器はこの順で読む。
pub(super) fn 突き合わせの引数を足す(
    並び: &mut 語の並び, 正解表のパス: &Path, ファイル一覧: &検査するファイル一覧
) {
    並び.パスを足す(正解表のパス);
    部品のファイルの並びを足す(並び, ファイル一覧);
}
