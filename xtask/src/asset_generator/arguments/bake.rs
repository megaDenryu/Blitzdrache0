//! 実行時形式を焼く指定だけが使う、材料の引数列を組み立てる。
//!
//! 材料を1つの型で束ねて渡すのは、7つの引数を並べて渡すと呼び出し側で順序を取り違えても型が通るためである。
//! 参照の寿命が指定の側に紐づくため、この型は指定を借りている間だけ生きる。

use blitz_asset_compiler::{
    ソースルート, テクスチャ格納方針, 実行時形式の出力ルート, 散布の焼き方, 遠景地形の焼き方
};

use super::spelling::方針の綴り;
use super::word_list::語の並び;
use crate::asset_generator::error::生成器エラー;
use crate::asset_generator::planting_count::同居植生の個体数;
use crate::asset_generator::world_name::世界名;

/// テクスチャ格納方針を選ぶ綴り。生成器側の解析境界にも同じ綴りがある。
const テクスチャ格納方針の選択肢の綴り: &str = "--texture-storage-policy";

/// 焼くときに渡す材料一式。
pub(super) struct 焼く材料<'指定> {
    pub(super) ソースルート: &'指定 ソースルート,
    pub(super) 出力ルート: &'指定 実行時形式の出力ルート,
    pub(super) 世界: 世界名,
    pub(super) 同居植生個体数: Option<同居植生の個体数>,
    pub(super) テクスチャ格納方針: Option<テクスチャ格納方針>,
    pub(super) 遠景地形: 遠景地形の焼き方,
    pub(super) 散布: 散布の焼き方,
}

pub(super) fn 焼く引数を足す(並び: &mut 語の並び, 材料: 焼く材料<'_>) -> Result<(), 生成器エラー> {
    並び.パスを足す(材料.ソースルート.プロセスの引数へ渡すディレクトリ());
    並び.パスを足す(材料.出力ルート.プロセスの引数へ渡すディレクトリ());
    並び.語を足す(材料.世界.綴り());
    並び.値を足す(None, "同居植生の個体数", 材料.同居植生個体数.map(同居植生の個体数::引数の綴り))?;
    並び.値を足す(
        Some(テクスチャ格納方針の選択肢の綴り),
        "テクスチャ格納方針の名前",
        材料.テクスチャ格納方針.map(方針の綴り),
    )?;
    if let Some(綴り) = 材料.遠景地形.引数へ足す綴り() {
        並び.語を足す(綴り);
    }
    if let Some(綴り) = 材料.散布.引数へ足す綴り() {
        並び.語を足す(綴り);
    }
    Ok(())
}
