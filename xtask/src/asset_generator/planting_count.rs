//! 同居植生の個体数: 地形の1チャンクへ同居させる植生の数。
//!
//! 裸の数や綴りで運ばないのは、生成器の位置引数がソースルート・出力ルート・世界名に続く4つ目であり、
//! 綴りのまま運ぶと世界名や方針の名前と取り違えても型が通るためである。物量計測は同じ世界を数だけ変えて
//! 何度も焼くため、この数の取り違えは「別の物量点を測った」という気付きにくい破れになる。

/// 注意: 綴りへ戻るのはプロセスの引数を組む1箇所だけである。
#[repr(transparent)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 同居植生の個体数(usize);

impl 同居植生の個体数 {
    pub const fn 生成する(個体数: usize) -> Self {
        Self(個体数)
    }

    pub fn 引数の綴り(self) -> String {
        self.0.to_string()
    }
}
