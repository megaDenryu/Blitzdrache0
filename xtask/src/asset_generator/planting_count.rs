//! 同居植生の個体数: 地形の1チャンクへ同居させる植生の数。
//!
//! 裸の数や綴りで運ばないのは、生成器の位置引数がソースルート・出力ルート・世界名に続く4つ目であり、
//! 綴りのまま運ぶと世界名や方針の名前と取り違えても型が通るためである。物量計測は同じ世界を数だけ変えて
//! 何度も焼くため、この数の取り違えは「別の物量点を測った」という気付きにくい破れになる。
//!
//! 人へ見せる口と生成器へ渡す口を分けるのは、後者が役割の型を生の語へ戻す境界であり、
//! その境界を器の外から呼べるようにすると、閉じたはずの生値化が報告や画面の行から漏れ出すためである。

use std::fmt;

#[repr(transparent)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 同居植生の個体数(usize);

impl 同居植生の個体数 {
    pub const fn 生成する(個体数: usize) -> Self {
        Self(個体数)
    }

    /// 注意: 生成器へ渡す語へ戻る口である。呼べるのは生成の引数を組む器の内側だけであり、
    /// 人へ見せる行は`Display`を通る。
    pub(super) fn 引数の綴り(self) -> String {
        self.0.to_string()
    }
}

/// 人へ見せるための綴り。報告の行がこれを通る。
impl fmt::Display for 同居植生の個体数 {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(書き手, "{}", self.0)
    }
}
