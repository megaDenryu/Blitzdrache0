//! アセット生成器の起こし方が返す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。
//! 様式は`acceptance/error.rs`に倣う。
//!
//! 生の文へ戻る変換をこの型が持たないのは、この生成器を呼ぶ入口がすべて型付きエラーへ移り終えたためである。

#[derive(Debug)]
pub enum 生成器エラー {
    生成器を起こせなかった { 生成器: &'static str, 誤り: std::io::Error },
    生成器が失敗して終わった { 生成器: &'static str, 終了状態: String },
    検査するファイルが1つも無い,                                   // 空の一覧で起こすと、生成器が何も検査せず成功を返す
    値が選択肢の綴りに見える { 役割: &'static str, 綴り: String }, // 生成器はこれを未知の選択肢として拒む
    生成器の実行ファイルの置き場を決められない { 生成器: &'static str, 誤り: std::io::Error },
}

impl std::error::Error for 生成器エラー {}

impl std::fmt::Display for 生成器エラー {
    fn fmt(&self, 書き手: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::生成器を起こせなかった { 生成器, 誤り } => {
                write!(書き手, "{生成器}を起動できなかった: {誤り}")
            }
            Self::生成器が失敗して終わった { 生成器, 終了状態 } => {
                write!(書き手, "{生成器}が{終了状態}で失敗した")
            }
            Self::検査するファイルが1つも無い => {
                write!(書き手, "検査するファイルが1つも無い")
            }
            Self::値が選択肢の綴りに見える { 役割, 綴り } => {
                write!(書き手, "{役割}として渡された{綴り}が選択肢の綴りに見える(生成器は未知の選択肢として拒む)")
            }
            Self::生成器の実行ファイルの置き場を決められない { 生成器, 誤り } => {
                write!(書き手, "{生成器}の実行ファイルの置き場を決められなかった: {誤り}")
            }
        }
    }
}
