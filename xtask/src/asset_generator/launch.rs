//! アセット生成器の起動: 1回ぶんのプロセス起動を、組み立ててから走らせるまで持つセッション型。
//!
//! 起こす手順をコールバックで挟まずこの型で表すのは、組み立てる・走らせる・終了状態を判定するの3手が
//! その場で1回ずつ実行される括りであるためである。様式は`acceptance/app_launch.rs`に倣う。
//!
//! 始める口が`生成の指定`だけを受けるのは、引数の検証をセッションを始める前に済ませるためである。
//! セッションの中で落とすと、未終了のセッションが破棄されて閉じ忘れのpanicが型付きエラーを隠す。
//!
//! 走らせて終わらせる局面は`terminate`が、閉じ忘れの検出は`drop_guard`が持つ。

mod drop_guard;
mod terminate;

use std::process::Command;

use super::arguments::完成した生成引数;
use super::error::生成器エラー;
use super::specification::生成の指定;

#[must_use]
pub struct アセット生成器の起動 {
    生成器: &'static str,
    コマンド: Command,
    終了済みか: bool, // 終端メソッドを通ったか。`Drop`がこれを見て閉じ忘れを落とす
}

impl アセット生成器の起動 {
    /// 指定を検証して組み立て、起こす手前まで進める。検証していない指定でセッションを作る形は書けない。
    pub fn 始める(指定: &生成の指定<'_>) -> Result<Self, 生成器エラー> {
        let mut コマンド = 指定.cargoの起動コマンドを組む();
        完成した生成引数::指定から組み立てる(指定)?.コマンドへ並べる(&mut コマンド);
        Ok(Self {
            生成器: 指定.生成器の名前(),
            コマンド,
            終了済みか: false,
        })
    }
}
