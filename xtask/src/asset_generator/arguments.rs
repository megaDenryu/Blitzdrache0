//! 完成した生成引数: 生成の指定から組み立て済みで、生成器がそのまま受け取れる語の並び。
//!
//! この型を通さないとセッションを始められない形にするのは、検証をセッションの中で行うと、検証が落ちたときに
//! 未終了のセッションが破棄されて閉じ忘れのpanicが起き、約束した型付きエラーが呼び出し元へ返らないためである。
//!
//! 選択肢の綴りをここが私有するのは、同じ綴りが生成器側
//! (`crates/blitz_asset_compiler/examples/generate_source_assets/generation_arguments.rs`)にもあり、
//! 食い違えば生成器が「知らない引数である」で失敗するためである。
//!
//! 並びを包むだけの口を置かないのは、未検証の語でセッションを作れないことを型の不変条件にするためである。
//! 積み方と値の検査は`word_list`が持つ。
//! 注意: ここが役割を持つパスの型を生の語へ戻す境界である。プロセスの引数は綴りでしか渡せない。

mod word_list;

use std::ffi::OsString;
use std::process::Command;

use super::error::生成器エラー;
use super::specification::生成の指定;
use word_list::語の並び;

/// 生成器へ種を渡す選択肢の綴り。
const 種の選択肢の綴り: &str = "--game-map-seed";
/// 生成器へソースルートを渡す選択肢の綴り。
const ソースルートの選択肢の綴り: &str = "--source-root";
/// 生成器へテクスチャ格納方針を渡す選択肢の綴り。この綴りの直後の1語が方針の名前である。
const テクスチャ格納方針の選択肢の綴り: &str = "--texture-storage-policy";

/// 注意: 値として渡す語が選択肢の綴りに見えないことと、検査するファイルが1つ以上あることがこの型の不変条件である。
/// 構築の口は`指定から組み立てる`だけであり、どちらも検証を通す。
#[repr(transparent)]
pub(super) struct 完成した生成引数(Vec<OsString>);

impl 完成した生成引数 {
    pub(super) fn 指定から組み立てる(指定: &生成の指定<'_>) -> Result<Self, 生成器エラー> {
        let mut 並び = 語の並び::空から始める();
        match 指定 {
            生成の指定::実行時形式を焼く {
                ソースルート,
                出力ルート,
                世界,
                同居植生個体数,
                テクスチャ格納方針の名前,
            } => {
                並び.パスを足す(ソースルート);
                並び.パスを足す(出力ルート);
                並び.語を足す(世界.綴り());
                並び.値を足す(None, "同居植生の個体数", *同居植生個体数)?;
                並び.値を足す(
                    Some(テクスチャ格納方針の選択肢の綴り),
                    "テクスチャ格納方針の名前",
                    *テクスチャ格納方針の名前,
                )?;
            }
            生成の指定::ソースアセットを生成する {
                場所巡りの世界の種,
                ソースルート,
            } => {
                並び.値を足す(Some(種の選択肢の綴り), "場所巡りの世界の種", *場所巡りの世界の種)?;
                if let Some(ルート) = ソースルート {
                    並び.語を足す(ソースルートの選択肢の綴り);
                    並び.パスを足す(ルート);
                }
            }
            生成の指定::入力するglTFの契約を検査する {
                検査するファイル一覧
            } => {
                if 検査するファイル一覧.is_empty() {
                    return Err(生成器エラー::検査するファイルが1つも無い);
                }
                for ファイル in *検査するファイル一覧 {
                    並び.語を足す(ファイル);
                }
            }
            生成の指定::アセットの変更を見張る {
                ソースルート, 出力ルート
            } => {
                並び.パスを足す(ソースルート);
                並び.パスを足す(出力ルート);
            }
        }
        Ok(Self(並び.取り出す()))
    }

    pub(super) fn コマンドへ並べる(&self, コマンド: &mut Command) {
        コマンド.args(&self.0);
    }
}
