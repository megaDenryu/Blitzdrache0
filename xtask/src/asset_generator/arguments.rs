//! 完成した生成引数: 生成の指定から組み立て済みで、生成器がそのまま受け取れる語の並び。
//!
//! この型を通さないとセッションを始められない形にするのは、組み立てをセッションの中で行うと、失敗したときに
//! 未終了のセッションが破棄されて閉じ忘れのpanicが起き、約束した型付きエラーが呼び出し元へ返らないためである。
//!
//! 選択肢の綴りをここが私有するのは、同じ綴りが生成器側
//! (`crates/blitz_asset_compiler/examples/generate_source_assets/generation_arguments.rs`)にもあり、
//! 食い違えば生成器が「知らない引数である」で失敗するためである。
//!
//! 注意: **ここが役割の型を生の語へ戻す唯一の境界である。** プロセスの引数は綴りでしか渡せない。
//! 指定の側は最後まで役割の型で運び、写しはこの器の中へ閉じる。値ごとの綴りは`spelling`が、
//! 積み方と値の検査は`word_list`が持つ。

mod source_assets;
mod spelling;
mod word_list;

use std::ffi::OsString;
use std::process::Command;

use super::error::生成器エラー;
use super::planting_count::同居植生の個体数;
use super::specification::生成の指定;
use source_assets::ソース生成の引数を足す;
use spelling::方針の綴り;
use word_list::語の並び;

/// 生成器へテクスチャ格納方針を渡す選択肢の綴り。この綴りの直後の1語が方針の名前である。
const テクスチャ格納方針の選択肢の綴り: &str = "--texture-storage-policy";

/// 注意: 値として渡す語が選択肢の綴りに見えないことがこの型の不変条件である。
/// 構築の口は`指定から組み立てる`だけであり、そこが検証を通す。
#[repr(transparent)]
pub(super) struct 完成した生成引数(Vec<OsString>);

impl 完成した生成引数 {
    pub(super) fn 指定から組み立てる(指定: &生成の指定<'_>) -> Result<Self, 生成器エラー> {
        let mut 並び = 語の並び::空から始める();
        match 指定 {
            生成の指定::実行時形式を焼く {
                ソースルート,
                出力ルート,
                世界,
                同居植生個体数,
                テクスチャ格納方針,
                遠景地形,
            } => {
                並び.パスを足す(ソースルート.プロセスの引数へ渡すディレクトリ());
                並び.パスを足す(出力ルート.プロセスの引数へ渡すディレクトリ());
                並び.語を足す(世界.綴り());
                並び.値を足す(None, "同居植生の個体数", 同居植生個体数.map(同居植生の個体数::引数の綴り))?;
                並び.値を足す(
                    Some(テクスチャ格納方針の選択肢の綴り),
                    "テクスチャ格納方針の名前",
                    テクスチャ格納方針.map(方針の綴り),
                )?;
                if let Some(綴り) = 遠景地形.引数へ足す綴り() {
                    並び.語を足す(綴り);
                }
            }
            生成の指定::ソースアセットを生成する {
                場所巡りの世界の種,
                ソースルート,
                世界の広がり,
            } => {
                ソース生成の引数を足す(&mut 並び, *場所巡りの世界の種, *ソースルート, *世界の広がり)?;
            }
            生成の指定::入力するglTFの契約を検査する {
                検査するファイル一覧
            } => {
                for ファイル in 検査するファイル一覧.一覧() {
                    並び.パスを足す(ファイル);
                }
            }
            生成の指定::アセットの変更を見張る {
                ソースルート, 出力ルート
            } => {
                並び.パスを足す(ソースルート.プロセスの引数へ渡すディレクトリ());
                並び.パスを足す(出力ルート.プロセスの引数へ渡すディレクトリ());
            }
        }
        Ok(Self(並び.取り出す()))
    }

    pub(super) fn コマンドへ並べる(&self, コマンド: &mut Command) {
        コマンド.args(&self.0);
    }
}
