//! 組み立て済みの起動を走らせて終わらせる局面。いつ呼ばれるかで組み立ての局面と分かれる。
//! ここの2つはその起動でちょうど1回だけ呼ばれ、呼んだ時点でセッションが閉じる。
//!
//! どちらも最初に終了済みへ遷移させる。プロセスを起こせなかった実行もセッションとしては閉じており、
//! そこで`Drop`が閉じ忘れとして落とすと、本当の失敗の理由が破棄の失敗に隠れる。

use super::super::error::生成器エラー;
use super::アセット生成器の起動;

impl アセット生成器の起動 {
    /// 標準出力も標準エラーもそのまま画面へ流したまま終わりを待つ。生成の進み具合を人が見る入口がこれを通る。
    pub fn 画面へ流したまま走らせて終わりを待つ(mut self) -> Result<(), 生成器エラー> {
        self.終了済みか = true;
        let 終了状態 = self.コマンド.status().map_err(|誤り| 生成器エラー::生成器を起こせなかった {
            生成器: self.生成器, 誤り
        })?;
        if 終了状態.success() {
            return Ok(());
        }
        Err(生成器エラー::生成器が失敗して終わった {
            生成器: self.生成器,
            終了状態: 終了状態.to_string(),
        })
    }

    /// 標準出力を取り込んで返す。増分が効いたかを外から見る材料が生成器の報告の行だけであるためである。
    /// 取り込んだ内容はそのまま画面へ出すため、人が見るものは流したときと変わらない。
    pub fn 走らせて標準出力を取り込む(mut self) -> Result<String, 生成器エラー> {
        self.終了済みか = true;
        let 出力 = self.コマンド.output().map_err(|誤り| 生成器エラー::生成器を起こせなかった {
            生成器: self.生成器, 誤り
        })?;
        let 標準出力 = String::from_utf8_lossy(&出力.stdout).into_owned();
        print!("{標準出力}");
        eprint!("{}", String::from_utf8_lossy(&出力.stderr));
        if 出力.status.success() {
            return Ok(標準出力);
        }
        Err(生成器エラー::生成器が失敗して終わった {
            生成器: self.生成器,
            終了状態: 出力.status.to_string(),
        })
    }
}
