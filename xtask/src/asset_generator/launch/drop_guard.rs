//! アセット生成器の起動の閉じ忘れの検出。触れるのは`終了済みか`と`生成器`だけであり、コマンドには触れない。
//!
//! `#[must_use]`だけでは足りないのは、その注記が「戻り値を捨てた」ことしか捕まえないためである。
//! 変数へ受けた後、終端メソッドを呼ばずスコープを抜ける形はそのまま通る。
//!
//! 回復可能な失敗でなくpanicにするのは、これが到達したらプログラムのバグだからである。組み立てるだけ組み立てて
//! 走らせない起動は、その入口が生成を1つも行わずに成功を返している状態であり、返す先が無い。

use super::アセット生成器の起動;

impl Drop for アセット生成器の起動 {
    fn drop(&mut self) {
        assert!(
            self.終了済みか,
            "アセット生成器の起動({})を終端メソッド(画面へ流したまま走らせて終わりを待つ・走らせて標準出力を取り込む)を呼ばずに捨てた",
            self.生成器
        );
    }
}
