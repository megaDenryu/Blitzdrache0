//! 生成の指定: どの生成器に何を作らせるかを枝で数え上げた型。
//!
//! 起こし方と引数を1つの枝へまとめるのは、生成器ごとに受け取る引数の形が違うためである。起こし方と引数を
//! 別々の型で持つと、ある生成器の起こし方へ別の生成器の引数を渡した形が型を通ってしまう。
//!
//! 材料を役割の型で受けるのは、ソースの置き場と生成物の置き場が同じ`Path`では取り違えても型が通り、
//! 乱数の種と個体数と方針の名前が同じ`&str`では取り違えても型が通るためである。
//! ソースルート・実行時形式の出力ルート・マップ生成の乱数の種・テクスチャ格納方針は生成器の側の語彙であり、
//! `blitz_asset_compiler`が正本を持つ。生の綴りへ写すのは`arguments`が組む引数の並びの1箇所だけである。
//!
//! example名の綴りをこの型が私有するのは、5つの入口がそれぞれ同じ綴りを書いていたためである。

use std::process::Command;

use blitz_asset_compiler::{
    ソースルート, テクスチャ格納方針, マップ生成の乱数の種, 世界の広がり, 実行時形式の出力ルート, 散布の焼き方, 検査する契約, 遠景地形の焼き方,
};

use super::inspection_files::検査するファイル一覧;
use super::planting_count::同居植生の個体数;
use super::world_name::世界名;

/// 生成器を収めているクレート。全部の枝が同じクレートのexampleである。
const 生成器のクレート: &str = "blitz_asset_compiler";

pub enum 生成の指定<'指定> {
    /// ソースアセットを版付き実行時形式へ焼く。
    実行時形式を焼く {
        ソースルート: &'指定 ソースルート,
        出力ルート: &'指定 実行時形式の出力ルート,
        世界: 世界名,
        /// 渡さない呼び出しは、生成器側の既定の密度で焼かれる。
        同居植生個体数: Option<同居植生の個体数>,
        /// 渡さない呼び出しは、生成器側の既定(`全てRGBA8`)で焼かれる。
        テクスチャ格納方針: Option<テクスチャ格納方針>,
        /// 世界に1枚だけの遠景地形を焼くか。大規模世界の生成だけが`焼く`を渡す。
        遠景地形: 遠景地形の焼き方,
        /// 地面へ散らす原型を焼くか。絵の対照を採る検収だけが`焼かない`を渡す。
        散布: 散布の焼き方,
    },
    /// 検証用のソースアセットを生成する。
    ソースアセットを生成する {
        /// 場所巡りの世界を種から作らせるときだけ渡す。
        場所巡りの世界の種: Option<マップ生成の乱数の種>,
        /// 既定のソースルート以外へ書き出させるときだけ渡す。
        ソースルート: Option<&'指定 ソースルート>,
        /// 場所巡りの既定3×3以外の広がりを生成するときだけ渡す。
        世界の広がり: Option<世界の広がり>,
    },
    /// glTFの入力契約を検査する。
    入力するglTFの契約を検査する {
        /// どちらの契約で読まれるファイルなのか。この実行の全ファイルへ同じに効く。
        検査する契約: 検査する契約,
        検査するファイル一覧: &'指定 検査するファイル一覧,
    },
    /// カタログの依存ファイルを見張り、変更のたびに実行時形式を焼き直す。
    アセットの変更を見張る {
        ソースルート: &'指定 ソースルート,
        出力ルート: &'指定 実行時形式の出力ルート,
    },
}

impl 生成の指定<'_> {
    /// この生成器を起こすcargoのコマンド。生成器自身の引数は`完成した生成引数`が続けて並べる。
    pub(super) fn cargoの起動コマンドを組む(&self) -> Command {
        let mut コマンド = Command::new("cargo");
        コマンド.arg("run");
        if self.構築の知らせを伏せるか() {
            コマンド.arg("--quiet");
        }
        コマンド.args(["-p", 生成器のクレート, "--example", self.生成器の名前(), "--"]);
        コマンド
    }

    /// 起こす生成器のexample名。破れの文面もこの名前で生成器を名指す。
    pub(super) fn 生成器の名前(&self) -> &'static str {
        match self {
            Self::実行時形式を焼く { .. } => "compile_assets",
            Self::ソースアセットを生成する { .. } => "generate_source_assets",
            Self::入力するglTFの契約を検査する { .. } => "check_glb",
            Self::アセットの変更を見張る { .. } => "watch_assets",
        }
    }

    /// cargo自身の構築の知らせを伏せるか。検査の結果だけを読む入口が伏せる。
    fn 構築の知らせを伏せるか(&self) -> bool {
        matches!(self, Self::入力するglTFの契約を検査する { .. })
    }
}
