//! 鍵に結ばれた値の語の探し方。触れるのは鍵の綴りと渡された行だけである。
//!
//! 形ごとに探し方を分けて持つのは、結ばれ方によって「鍵が無い」と「鍵はあるが値が無い」の見分け方が違うためである。
//! 語を切って次を見る形では次の語の不在が値の不在であり、1語に続く形では鍵の後ろの残りが空であることが値の不在である。
//!
//! 注意: どの形も、空の綴りを`見つかった`で返してはならない。返すと「鍵はあるが値が無い」が
//! 後段の「数として読めない」へ化ける。この不変条件の反証は`binding_tests`が持つ。

use super::{報告の行の鍵, 鍵に値が結ばれる形, 鍵に結ばれた語の在り処};

impl 報告の行の鍵 {
    /// この鍵に結ばれた値の語を探す。鍵が無いことと、鍵はあるが値が無いことを別の枝で返す。
    pub fn 結ばれた語を探す<'行>(&self, 行: &'行 str, 形: 鍵に値が結ばれる形) -> 鍵に結ばれた語の在り処<'行> {
        match 形 {
            鍵に値が結ばれる形::次の語が値である => self.語の次を探す(行, |語| 語 == self.0.as_ref()),
            鍵に値が結ばれる形::この綴りで終わる語の次が値である => {
                self.語の次を探す(行, |語| 語.ends_with(self.0.as_ref()))
            }
            鍵に値が結ばれる形::この綴りに続く残りが値である => self.語の残りを探す(行),
            鍵に値が結ばれる形::この綴りに続く数字の並びが値である => self.続く数字の並びを探す(行),
            鍵に値が結ばれる形::等号の後ろが値である => self.等号の後ろを探す(行),
        }
    }

    fn 語の次を探す<'行>(&self, 行: &'行 str, 一致か: impl Fn(&str) -> bool) -> 鍵に結ばれた語の在り処<'行> {
        let mut 語一覧 = 行.split_whitespace().skip_while(|語| !一致か(語));
        if 語一覧.next().is_none() {
            return 鍵に結ばれた語の在り処::鍵が無い;
        }
        語一覧
            .next()
            .map_or(鍵に結ばれた語の在り処::鍵に値が続いていない, 鍵に結ばれた語の在り処::見つかった)
    }

    /// 「標本60)」のように鍵と値が1語に続く形。鍵で始まる語の残りを値とする。
    fn 語の残りを探す<'行>(&self, 行: &'行 str) -> 鍵に結ばれた語の在り処<'行> {
        行.split_whitespace()
            .find_map(|語| 語.strip_prefix(self.0.as_ref()))
            .map_or(鍵に結ばれた語の在り処::鍵が無い, 鍵の後ろの残りを在り処へ写す)
    }

    /// 鍵の後ろに続く数字の並び。語の切れ目でなく数字でない文字で止めるのは、読点で区切る行が
    /// 「全画素921600、1画素の幅0.001389を超えた画素0」のように鍵と値と次の鍵を1語へ連ねるためである。
    fn 続く数字の並びを探す<'行>(&self, 行: &'行 str) -> 鍵に結ばれた語の在り処<'行> {
        let Some((_, 鍵の後ろ)) = 行.split_once(self.0.as_ref()) else {
            return 鍵に結ばれた語の在り処::鍵が無い;
        };
        let 桁数 = 鍵の後ろ.chars().take_while(|文字| 文字.is_ascii_digit() || *文字 == '.').count();
        鍵の後ろの残りを在り処へ写す(&鍵の後ろ[..桁数])
    }

    /// 「鍵=値」の形。等号を持たない鍵だけの語も鍵が在ることの証拠として数えるのは、この型が
    /// 「鍵が無い」と「鍵はあるが値が無い」を別の枝で数えているためである。
    fn 等号の後ろを探す<'行>(&self, 行: &'行 str) -> 鍵に結ばれた語の在り処<'行> {
        let 等号まで = format!("{}=", self.0);
        let mut 鍵だけの語が在るか = false;
        for 語 in 行.split_whitespace() {
            if let Some(残り) = 語.strip_prefix(等号まで.as_str()) {
                return 鍵の後ろの残りを在り処へ写す(残り);
            }
            鍵だけの語が在るか = 鍵だけの語が在るか || 語 == self.0.as_ref();
        }
        if 鍵だけの語が在るか {
            return 鍵に結ばれた語の在り処::鍵に値が続いていない;
        }
        鍵に結ばれた語の在り処::鍵が無い
    }
}

/// 鍵の後ろの残りを在り処の枝へ写す。空の残りは値でなく、値が続いていないことである。
fn 鍵の後ろの残りを在り処へ写す(残り: &str) -> 鍵に結ばれた語の在り処<'_> {
    if 残り.is_empty() {
        return 鍵に結ばれた語の在り処::鍵に値が続いていない;
    }
    鍵に結ばれた語の在り処::見つかった(残り)
}
