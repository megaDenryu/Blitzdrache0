//! 鍵に結ばれた語を探した結果が、型の数えた3つの枝どおりに分かれることの反証。
//!
//! 「鍵はあるが値が無い」を`見つかった("")`で返す実装は、後段の「数として読めない」へ破れを化けさせる。
//! 直す側が見る場所が「アプリが値を出していない」から「行の書式が変わった」へずれるため、形ごとに固定する。

use super::{報告の行の鍵, 鍵に値が結ばれる形, 鍵に結ばれた語の在り処};

const 鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("標本");

fn 探す(行: &str, 形: 鍵に値が結ばれる形) -> 在り処の呼び名 {
    match 鍵.結ばれた語を探す(行, 形) {
        鍵に結ばれた語の在り処::見つかった(語) => 在り処の呼び名::見つかった(語.to_string()),
        鍵に結ばれた語の在り処::鍵が無い => 在り処の呼び名::鍵が無い,
        鍵に結ばれた語の在り処::鍵に値が続いていない => 在り処の呼び名::鍵に値が続いていない,
    }
}

/// 検査が結果を突き合わせるための写し。在り処は借用を持つため、比べやすい形へ写して使う。
#[derive(Debug, PartialEq, Eq)]
enum 在り処の呼び名 {
    見つかった(String),
    鍵が無い,
    鍵に値が続いていない,
}

fn 見つかった(語: &str) -> 在り処の呼び名 {
    在り処の呼び名::見つかった(語.to_string())
}

#[test]
fn 次の語が値である形は鍵のみと鍵の末尾を見分ける() {
    let 形 = 鍵に値が結ばれる形::次の語が値である;
    assert_eq!(探す("標本 60", 形), 見つかった("60"));
    assert_eq!(探す("標本", 形), 在り処の呼び名::鍵に値が続いていない);
    assert_eq!(探す("窓 60", 形), 在り処の呼び名::鍵が無い);
}

#[test]
fn この綴りに続く残りが値である形は鍵だけの語を値と読まない() {
    let 形 = 鍵に値が結ばれる形::この綴りに続く残りが値である;
    assert_eq!(探す("標本60)", 形), 見つかった("60)"));
    assert_eq!(探す("標本", 形), 在り処の呼び名::鍵に値が続いていない);
    assert_eq!(探す("窓60", 形), 在り処の呼び名::鍵が無い);
}

#[test]
fn 等号の後ろが値である形は鍵のみと等号だけを見分ける() {
    let 形 = 鍵に値が結ばれる形::等号の後ろが値である;
    assert_eq!(探す("標本=60", 形), 見つかった("60"));
    assert_eq!(探す("標本=", 形), 在り処の呼び名::鍵に値が続いていない);
    assert_eq!(探す("標本", 形), 在り処の呼び名::鍵に値が続いていない);
    assert_eq!(探す("窓=60", 形), 在り処の呼び名::鍵が無い);
}

/// 鍵だけの語が先に並んでも、後ろに値を結んだ語があればそちらを採る。
#[test]
fn 等号の後ろが値である形は鍵だけの語より値を結んだ語を優先する() {
    assert_eq!(探す("標本 標本=60", 鍵に値が結ばれる形::等号の後ろが値である), 見つかった("60"));
}

#[test]
fn この綴りに続く数字の並びが値である形は数字の無い後ろを値と読まない() {
    let 形 = 鍵に値が結ばれる形::この綴りに続く数字の並びが値である;
    assert_eq!(探す("全画素921600、標本60、次", 形), 見つかった("60"));
    assert_eq!(探す("全画素921600、標本なし", 形), 在り処の呼び名::鍵に値が続いていない);
    assert_eq!(探す("全画素921600", 形), 在り処の呼び名::鍵が無い);
}

#[test]
fn この綴りで終わる語の次が値である形は触れた区切りを越えて値を採る() {
    let 形 = 鍵に値が結ばれる形::この綴りで終わる語の次が値である;
    assert_eq!(探す("(標本 60", 形), 見つかった("60"));
    assert_eq!(探す("(標本", 形), 在り処の呼び名::鍵に値が続いていない);
    assert_eq!(探す("(窓 60", 形), 在り処の呼び名::鍵が無い);
}
