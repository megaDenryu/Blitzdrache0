use super::*;

#[test]
fn 数字入力があれば数字の位置を優先する() {
    let mut 状態 = メニュー表示状態::生成する(10);
    状態.下へ移動する();
    状態.数字を追加する('5');
    assert_eq!(状態.選択位置(), Some(4));
}

#[test]
fn 数字入力が無ければカーソル位置を使う() {
    let mut 状態 = メニュー表示状態::生成する(10);
    状態.下へ移動する();
    状態.下へ移動する();
    assert_eq!(状態.選択位置(), Some(2));
}

#[test]
fn 範囲外の番号はnone() {
    let mut 状態 = メニュー表示状態::生成する(3);
    状態.数字を追加する('9');
    assert_eq!(状態.選択位置(), None);
}

#[test]
fn 表示窓はカーソルを常に含む() {
    let mut 状態 = メニュー表示状態::生成する(100);
    for _ in 0..30 {
        状態.下へ移動する();
    }
    状態.表示窓を追従させる(10);
    assert!(状態.表示窓開始() <= 状態.カーソル位置());
    assert!(状態.カーソル位置() < 状態.表示窓開始() + 10);
}
