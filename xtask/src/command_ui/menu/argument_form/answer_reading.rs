//! 入力の1行を、その引数定義に対する答えへ読む規則。受け取るのは引数定義と入力の行、返すのは
//! コマンド行へ足す語の並びか、読み手へ返す聞き直しの理由である。
//!
//! 標準入出力に触れない工程としてフォーム本体から分けるのは、空Enterでの省略・必須の聞き直し・
//! 番号から綴りへの変換という判断を、入力の口を用意せずに試験できるようにするためである。

#[cfg(test)]
mod tests;

use crate::command_ui::command_catalog::{引数定義, 省略したときの扱い, 選択肢};
use crate::command_ui::menu::argument_line;

pub(super) enum 引数の答え {
    語へ写した(Vec<String>),
    聞き直す(String),
}

pub(super) fn 答えを読む(定義: 引数定義, 行: &str) -> 引数の答え {
    let 入力 = 行.trim();
    match 定義 {
        引数定義::有無だけの旗 { 綴り, .. } => 旗の答えを読む(綴り, 入力),
        引数定義::名前に続けて渡す値 { 綴り, 扱い, .. } => 名前つきの値の答えを読む(綴り, 扱い, 入力),
        引数定義::綴りから1つ選ぶ値 {
            名前, 扱い, 選択肢一覧,
        ..
        } => 選んだ綴りの答えを読む(名前, 扱い, 選択肢一覧, 入力),
        引数定義::位置で渡す値 { 扱い, .. } if 入力.is_empty() => 省いた答え(扱い),
        引数定義::位置で渡す値 { .. } => 引数の答え::語へ写した(vec![入力.to_string()]),
        引数定義::位置で何個でも渡す値 { 扱い, .. } => 何個でもの答えを読む(扱い, 行),
        引数定義::そのまま子へ渡す残りの語 { .. } => 語へ分けた答えを読む(行),
    }
}

/// 省いたときの答え。省ける引数は語を1つも足さず、省けない引数は理由を告げて聞き直させる。
fn 省いた答え(扱い: 省略したときの扱い) -> 引数の答え {
    if 扱い.省いて進めるか() {
        引数の答え::語へ写した(Vec::new())
    } else {
        引数の答え::聞き直す("この引数は省けない。値を入れてEnterする".to_string())
    }
}

fn 旗の答えを読む(綴り: &str, 入力: &str) -> 引数の答え {
    match 入力 {
        "" | "n" | "N" => 引数の答え::語へ写した(Vec::new()),
        "y" | "Y" => 引数の答え::語へ写した(vec![綴り.to_string()]),
        _ => 引数の答え::聞き直す("yで有効にする。空Enterまたはnで無効のままにする".to_string()),
    }
}

fn 名前つきの値の答えを読む(綴り: &str, 扱い: 省略したときの扱い, 入力: &str) -> 引数の答え {
    if 入力.is_empty() {
        return 省いた答え(扱い);
    }
    引数の答え::語へ写した(vec![綴り.to_string(), 入力.to_string()])
}

/// 番号で選ばせ、選ばれた綴りへ写す。名前を持つ引数は名前の語を先に置く。
fn 選んだ綴りの答えを読む(
    名前: Option<&str>, 扱い: 省略したときの扱い, 選択肢一覧: &[選択肢], 入力: &str
) -> 引数の答え {
    if 入力.is_empty() {
        return 省いた答え(扱い);
    }
    let 選んだもの = 入力
        .parse::<usize>()
        .ok()
        .and_then(|番号| 番号.checked_sub(1))
        .and_then(|添字| 選択肢一覧.get(添字));
    let Some(選択肢) = 選んだもの else {
        return 引数の答え::聞き直す(format!("1から{}までの番号で選ぶ", 選択肢一覧.len()));
    };
    let mut 語一覧: Vec<String> = 名前.into_iter().map(str::to_string).collect();
    語一覧.push(選択肢.綴り().to_string());
    引数の答え::語へ写した(語一覧)
}

fn 何個でもの答えを読む(扱い: 省略したときの扱い, 行: &str) -> 引数の答え {
    match 語へ分けた答えを読む(行) {
        引数の答え::語へ写した(語一覧) if 語一覧.is_empty() => 省いた答え(扱い),
        答え => 答え,
    }
}

fn 語へ分けた答えを読む(行: &str) -> 引数の答え {
    match argument_line::語へ分ける(行) {
        Ok(語一覧) => 引数の答え::語へ写した(語一覧),
        Err(破れ) => 引数の答え::聞き直す(破れ.to_string()),
    }
}
