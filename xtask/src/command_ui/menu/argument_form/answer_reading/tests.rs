//! 入力1行から答えを読む規則の試験。標準入力を使わず、行の綴りと引数定義だけを与えて確かめる。

use crate::command_ui::command_catalog::引数定義;
use crate::command_ui::command_catalog::省略したときの扱い::{受け付けずに聞き直す, 実装の既定に任せる};

use super::{引数の答え, 答えを読む};

fn 語へ写した結果(定義: 引数定義, 行: &str) -> Vec<String> {
    match 答えを読む(定義, 行) {
        引数の答え::語へ写した(語一覧) => 語一覧,
        引数の答え::聞き直す(理由) => panic!("語へ写せると期待した答えが聞き直しになった: {理由}"),
    }
}

fn 聞き直しになるか(定義: 引数定義, 行: &str) -> bool {
    matches!(答えを読む(定義, 行), 引数の答え::聞き直す(_))
}

#[test]
fn 名前つきの値は名前と値の2語になる() {
    let 定義 = 引数定義::名前に続けて渡す値を定義する("--frames", "フレーム数", 実装の既定に任せる("160"));
    assert_eq!(語へ写した結果(定義, " 240 \n"), ["--frames", "240"]);
    assert!(語へ写した結果(定義, "\n").is_empty());
}

#[test]
fn 旗は肯定と否定と読めない答えを見分ける() {
    let 定義 = 引数定義::有無だけの旗を定義する("--print-plan", "計画だけ表示する");
    assert_eq!(語へ写した結果(定義, "y\n"), ["--print-plan"]);
    assert!(語へ写した結果(定義, "n\n").is_empty());
    assert!(聞き直しになるか(定義, "はい\n"));
}

#[test]
fn 何個でも渡す値は引用符の規則で語へ分かれる() {
    let 定義 = 引数定義::位置で何個でも渡す値を定義する("パス", "検査するパス", 受け付けずに聞き直す);
    assert_eq!(語へ写した結果(定義, "壁 \"柱 と 梁\"\n"), ["壁", "柱 と 梁"]);
    assert!(聞き直しになるか(定義, "\n"), "1つ以上を課す引数を空で通してはならない");
    assert!(聞き直しになるか(定義, "\"閉じ忘れ\n"), "引用符の閉じ忘れを黙って通してはならない");
}

#[test]
fn 位置で渡す値は空のとき扱いに従う() {
    let 省ける = 引数定義::位置で渡す値を定義する("フレーム数", "条件Aのフレーム数", 実装の既定に任せる("3600"));
    let 省けない = 引数定義::位置で渡す値を定義する("建物定義ID", "焼く建物の識別子", 受け付けずに聞き直す);
    assert!(語へ写した結果(省ける, "\n").is_empty());
    assert!(聞き直しになるか(省けない, "\n"));
    assert_eq!(語へ写した結果(省けない, "cabin\n"), ["cabin"]);
}
