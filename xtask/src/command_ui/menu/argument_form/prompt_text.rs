//! 引数1件について画面へ出す案内の文面。受け取るのは引数定義、返すのは見出し・説明・選べる綴り・
//! 省いたときの扱い・入力の促しを並べた複数行の綴りである。
//!
//! 文面の組み立てを入出力から分けるのは、どの形の引数でも「何を聞かれているか」「省けるのか」
//! 「何を打てばよいか」の3つが必ず並ぶことを、表示せずに確かめられるようにするためである。

use crate::command_ui::command_catalog::{引数定義, 省略したときの扱い, 選択肢};

pub(super) fn 案内文を組み立てる(定義: 引数定義) -> String {
    match 定義 {
        引数定義::有無だけの旗 { 綴り, 説明 } => {
            format!("{綴り}\n  {説明}\n  yで有効にする。空Enterで無効のまま次へ進む:")
        }
        引数定義::名前に続けて渡す値 { 綴り, 説明, 扱い } => {
            format!("{綴り} <値>\n  {説明}\n{}\n  値を入力してEnter:", 省いたときの案内(扱い))
        }
        引数定義::綴りから1つ選ぶ値 {
            名前,
            見出し,
            説明,
            扱い,
            選択肢一覧,
        } => 選ぶ引数の案内文(名前, 見出し, 説明, 扱い, 選択肢一覧),
        引数定義::位置で渡す値 { 見出し, 説明, 扱い } => {
            format!("<{見出し}>\n  {説明}\n{}\n  値を入力してEnter:", 省いたときの案内(扱い))
        }
        引数定義::位置で何個でも渡す値 { 見出し, 説明, 扱い } => {
            format!(
                "<{見出し}...>\n  {説明}\n{}\n  空白区切りで入力してEnter(空白を含む語は\"...\"で囲む):",
                省いたときの案内(扱い)
            )
        }
        引数定義::そのまま子へ渡す残りの語 { 見出し, 説明 } => {
            format!("<{見出し}...>\n  {説明}\n  空Enterで何も渡さない\n  空白区切りで入力してEnter:")
        }
    }
}

/// 位置で意味が決まる引数を、手前の位置の引数を省いたために尋ねられないと告げる文面。
pub(super) fn 飛ばしたことの案内(定義: 引数定義) -> String {
    format!(
        "\n{}は、手前の位置の引数を省いたため渡せない(位置がずれる)。飛ばして次へ進む",
        定義.見出し()
    )
}

fn 選ぶ引数の案内文(
    名前: Option<&str>, 見出し: &str, 説明: &str, 扱い: 省略したときの扱い, 選択肢一覧: &[選択肢]
) -> String {
    let 見出しの行 = match 名前 {
        Some(名前) => format!("{名前} <{見出し}>"),
        None => format!("<{見出し}>"),
    };
    let 選べる綴り = 選択肢一覧
        .iter()
        .enumerate()
        .map(|(添字, 選択肢)| format!("  {番号:>2}. {} — {}", 選択肢.綴り(), 選択肢.説明(), 番号 = 添字 + 1))
        .collect::<Vec<String>>()
        .join("\n");
    format!("{見出しの行}\n  {説明}\n{選べる綴り}\n{}\n  番号を入力してEnter:", 省いたときの案内(扱い))
}

fn 省いたときの案内(扱い: 省略したときの扱い) -> String {
    match 扱い.既定の説明() {
        Some(既定) => format!("  空Enterで省ける(省いたときの既定は{既定})"),
        None if 扱い.省いて進めるか() => "  空Enterで省ける".to_string(),
        None => "  省けない引数である".to_string(),
    }
}
