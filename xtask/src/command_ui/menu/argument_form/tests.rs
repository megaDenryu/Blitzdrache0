//! フォームのふるまいの試験。台本の読み手で駆動し、標準入力を使わずに空Enterの省略・必須の聞き直し・
//! 番号から綴りへの変換・位置がずれるときの飛ばしを確かめる。

use crate::command_ui::command_catalog::省略したときの扱い::{受け付けずに聞き直す, 語を1つも足さない};
use crate::command_ui::command_catalog::{引数定義, 選択肢};

use super::{引数フォーム, 行の読み手};

struct 台本の読み手 {
    行一覧: Vec<String>,
    読んだ数: usize,
}

impl 台本の読み手 {
    fn 生成する(行一覧: &[&str]) -> Self {
        Self {
            行一覧: 行一覧.iter().map(|行| (*行).to_string()).collect(),
            読んだ数: 0,
        }
    }
}

impl 行の読み手 for 台本の読み手 {
    fn 一行受け取る(&mut self) -> Option<String> {
        let 行 = self.行一覧.get(self.読んだ数)?.clone();
        self.読んだ数 += 1;
        Some(行)
    }
}

/// 台本を読ませてコマンド行の語と、実際に読んだ行数を返す。読んだ行数は「尋ねなかった」ことの証拠になる。
fn 台本で尋ねる(定義一覧: &[引数定義], 台本: &[&str]) -> (Vec<String>, usize) {
    let mut フォーム = 引数フォーム::生成する(台本の読み手::生成する(台本));
    let 語一覧 = フォーム.語一覧を尋ねる(定義一覧);
    (語一覧, フォーム.読み手.読んだ数)
}

#[test]
fn 必須の引数は空で答えると聞き直す() {
    let 定義一覧 = [引数定義::名前に続けて渡す値を定義する(
        "--seed",
        "乱数の種",
        受け付けずに聞き直す,
    )];
    let (語一覧, 読んだ数) = 台本で尋ねる(&定義一覧, &["", "12345"]);
    assert_eq!(語一覧, ["--seed", "12345"]);
    assert_eq!(読んだ数, 2);
}

#[test]
fn 省ける引数は空で答えると語を1つも足さない() {
    let 定義一覧 = [引数定義::名前に続けて渡す値を定義する(
        "--frames",
        "フレーム数",
        語を1つも足さない,
    )];
    let (語一覧, 読んだ数) = 台本で尋ねる(&定義一覧, &[""]);
    assert!(語一覧.is_empty());
    assert_eq!(読んだ数, 1);
}

#[test]
fn 旗はyで綴りを足し空のままなら足さない() {
    let 定義一覧 = [引数定義::有無だけの旗を定義する("--bake-only", "焼きまでで止める")];
    assert_eq!(台本で尋ねる(&定義一覧, &["y"]).0, ["--bake-only"]);
    assert!(台本で尋ねる(&定義一覧, &[""]).0.is_empty());
}

#[test]
fn 選択肢は番号を綴りへ写し名前があれば名前も足す() {
    const 選択肢一覧: &[選択肢] = &[選択肢::生成する("terrain", "地形"), 選択肢::生成する("range", "影の視距離")];
    let 定義一覧 = [引数定義::綴りから1つ選ぶ値を定義する(
        Some("--layout"),
        "構図",
        "構図を選ぶ",
        受け付けずに聞き直す,
        選択肢一覧,
    )];
    let (語一覧, 読んだ数) = 台本で尋ねる(&定義一覧, &["3", "2"]);
    assert_eq!(語一覧, ["--layout", "range"]);
    assert_eq!(読んだ数, 2);
}

#[test]
fn 位置の引数を省いたら後ろの位置の引数を尋ねない() {
    let 定義一覧 = [
        引数定義::位置で渡す値を定義する("ソースルート", "ソースのルート", 語を1つも足さない),
        引数定義::位置で渡す値を定義する("出力ルート", "出力のルート", 受け付けずに聞き直す),
        引数定義::有無だけの旗を定義する("--print-plan", "計画だけ表示する"),
    ];
    let (語一覧, 読んだ数) = 台本で尋ねる(&定義一覧, &["", "y"]);
    assert_eq!(語一覧, ["--print-plan"]);
    assert_eq!(読んだ数, 2);
}

#[test]
fn 入力が閉じたらそこまでの語を返す() {
    let 定義一覧 = [
        引数定義::位置で何個でも渡す値を定義する("パス", "検査するパス", 受け付けずに聞き直す),
        引数定義::有無だけの旗を定義する("--part", "部品の契約で検査する"),
    ];
    let (語一覧, 読んだ数) = 台本で尋ねる(&定義一覧, &["壁 柱"]);
    assert_eq!(語一覧, ["壁", "柱"]);
    assert_eq!(読んだ数, 1);
}
