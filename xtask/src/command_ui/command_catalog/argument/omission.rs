//! 引数を空のまま送ったときに何が起きるかの3通り。
//!
//! 「必須か」の真偽値でなく判別共用体で持つのは、省いてよい引数に「実装が既定を持つもの」と
//! 「持たないもの」の2通りがあり、フォームが読み手へ告げる文面がその2つで違うためである。
//! 既定の綴りを`Option<&str>`で別に持つ形にすると、必須なのに既定がある状態を型が許してしまう。

#[derive(Clone, Copy)]
pub(crate) enum 省略したときの扱い {
    受け付けずに聞き直す,
    実装の既定に任せる(&'static str),
    語を1つも足さない,
}

impl 省略したときの扱い {
    /// 空のまま次の引数へ進めるか。必須の引数だけが偽を返す。
    pub(crate) fn 省いて進めるか(self) -> bool {
        !matches!(self, Self::受け付けずに聞き直す)
    }

    /// 省いたときに効く既定の説明。実装が既定を持たない引数は無しを返す。
    pub(crate) fn 既定の説明(self) -> Option<&'static str> {
        match self {
            Self::実装の既定に任せる(説明) => Some(説明),
            Self::受け付けずに聞き直す | Self::語を1つも足さない => None,
        }
    }
}
