//! 引数定義と、一覧の説明文が見せている使い方の突き合わせ。定義は`menu`のフォームが読み、使い方の行は
//! 人が読む。2つが別々に書かれている以上、片方だけを直した食い違いはここでしか落とせない。
//!
//! 見るのは説明文のうち引数の構文の部分だけである。日本語の説明の中に出る綴り(他コマンドの引数の言及や
//! 外部コマンドの選択肢)は引数の宣言ではないため、宣言と突き合わせる対象にしない。

use super::{全件, 引数定義};

/// 1件の定義がコマンド行へ出しうる綴りを全部並べる。選択肢の綴りも、選ばれればコマンド行へ出る。
fn 定義が持つ綴り一覧(定義: 引数定義) -> Vec<&'static str> {
    match 定義 {
        引数定義::有無だけの旗 { 綴り, .. } | 引数定義::名前に続けて渡す値 { 綴り, .. } => vec![綴り],
        引数定義::綴りから1つ選ぶ値 { 名前, 選択肢一覧, .. } => {
            let mut 綴り一覧: Vec<&'static str> = 名前.into_iter().collect();
            綴り一覧.extend(選択肢一覧.iter().map(|選択肢| 選択肢.綴り()));
            綴り一覧
        }
        引数定義::位置で渡す値 { .. } | 引数定義::位置で何個でも渡す値 { .. } | 引数定義::そのまま子へ渡す残りの語 { .. } => {
            Vec::new()
        }
    }
}

fn コマンドの綴り一覧(項目: &super::コマンド項目) -> Vec<&'static str> {
    項目.引数定義一覧().iter().copied().flat_map(定義が持つ綴り一覧).collect()
}

#[test]
fn 使い方の引数の構文に出る名前は引数定義に在る() {
    for 項目 in 全件() {
        let 綴り一覧 = コマンドの綴り一覧(&項目);
        for 名指しされた綴り in 項目.引数の構文().名指しされた引数の綴り一覧() {
            assert!(
                綴り一覧.contains(&名指しされた綴り),
                "{}の使い方に出る{名指しされた綴り}に対応する引数定義が無い",
                項目.ascii名()
            );
        }
    }
}

#[test]
fn 引数の構文の有無と引数定義の有無が一致する() {
    for 項目 in 全件() {
        assert_eq!(
            項目.引数の構文().空か(),
            項目.引数定義一覧().is_empty(),
            "{}の使い方の引数の構文と引数定義の有無が食い違っている(構文: {})",
            項目.ascii名(),
            項目.引数の構文().綴り()
        );
    }
}

#[test]
fn 名前を持つ引数の綴りはハイフン2つで始まり位置の引数の見出しはハイフンで始まらない() {
    for 項目 in 全件() {
        for 定義 in 項目.引数定義一覧().iter().copied() {
            let 名指し = match 定義 {
                引数定義::有無だけの旗 { 綴り, .. } | 引数定義::名前に続けて渡す値 { 綴り, .. } => Some(綴り),
                引数定義::綴りから1つ選ぶ値 { 名前, .. } => 名前,
                引数定義::位置で渡す値 { .. } | 引数定義::位置で何個でも渡す値 { .. } | 引数定義::そのまま子へ渡す残りの語 { .. } => {
                    None
                }
            };
            match 名指し {
                Some(綴り) => assert!(綴り.starts_with("--"), "{}の{綴り}がハイフン2つで始まっていない", 項目.ascii名()),
                None => assert!(
                    !定義.見出し().starts_with('-'),
                    "{}の位置で渡す引数の見出し({})がハイフンで始まっている",
                    項目.ascii名(),
                    定義.見出し()
                ),
            }
        }
    }
}

#[test]
fn 同じコマンドの中で綴りが重複しない() {
    for 項目 in 全件() {
        let mut 綴り一覧 = コマンドの綴り一覧(&項目);
        let 件数 = 綴り一覧.len();
        綴り一覧.sort_unstable();
        綴り一覧.dedup();
        assert_eq!(綴り一覧.len(), 件数, "{}の引数定義に同じ綴りが2つ以上ある", 項目.ascii名());
    }
}
