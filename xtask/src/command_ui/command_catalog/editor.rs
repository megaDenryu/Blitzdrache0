//! エディター関連コマンドの一覧と、その引数の定義。担当するのは、ブラウザ版ゲーム開発用エディターの
//! 起動・建物外形カタログの書き出し・建物1棟だけの焼き・Rust側の型契約の書き出しの4件である。
//! `--project`の定義を1つ持って3件で分け合うのは、3件とも同じ解決規則(`editor/project_root.rs`)を通るためである。
//! 参照: `_doc/計画/ゲーム開発用エディター計画.md`

use super::argument::引数定義;
use super::argument::省略したときの扱い::{受け付けずに聞き直す, 実装の既定に任せる};
