//! `コマンド項目`が説明文から取り出す4つの綴り(ASCIIコマンド名・使い方の行・引数の構文・要約)の試験。

use super::コマンド項目;

#[test]
fn 先頭語をascii名として取り出す() {
    let 項目 = コマンド項目::引数なしで生成する("検証の標準列", "  verify           検証の標準列を実行する");
    assert_eq!(項目.ascii名(), "verify");
}

#[test]
fn 短い説明はそのまま返す() {
    let 項目 = コマンド項目::引数なしで生成する("起動スモーク確認", "  smoke  短い説明");
    assert_eq!(項目.要約(20), "短い説明");
}

#[test]
fn 長い説明は切り詰めて省略記号を付ける() {
    let 項目 = コマンド項目::引数なしで生成する("テスト", "  cmd  あいうえおかきくけこ");
    assert_eq!(項目.要約(5), "あいうえお…");
}

#[test]
fn 引数を取らない項目の引数の構文は空になる() {
    let 項目 = コマンド項目::引数なしで生成する("検証の標準列", "  verify           検証の標準列を実行する");
    assert_eq!(項目.引数の構文(), "");
    assert!(項目.引数定義一覧().is_empty());
}

#[test]
fn 引数の構文は説明の手前までを返す() {
    let 項目 = コマンド項目::引数なしで生成する("距離区分影の境界確認", "  csm-seam [--large-world]  低い太陽の地形世界を描く");
    assert_eq!(項目.引数の構文(), "[--large-world]");
}
