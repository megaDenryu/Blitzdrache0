//! 1つの物量点の結果と、そこから導く個体あたり費用。触れるのは実行の一覧だけであり、実行そのものは起こさない。
//! 個体あたり費用を持つのは、折れ点の判定が「区間が予算を超えたか」と「個体あたり費用が実行間ノイズ帯を超えて悪化したか」の
//! 2つで行われ、後者には物量で割った値が要るためである(参照: `_doc/設計/植生インスタンスと物量計測.md`「物量計測と折れ点の規則」)。

use super::run::一回の実行;

pub(super) struct 物量点の結果 {
    pub(super) 名前: String,
    pub(super) チャンクあたり個体数: usize,
    /// validationレイヤーが有効なデバッグビルドの実行が最終フレームに数えた候補数。レイヤーの検査を
    /// どの物量で通したかを、リリース実行の候補数とは別に残す。
    pub(super) 検査候補数: u64,
    pub(super) 実行一覧: Vec<一回の実行>,
}

impl 物量点の結果 {
    /// 群選択p50が中央にある実行。実行間の振れを1つ選ぶときに最小でも最大でもない値を採るためである。
    pub(super) fn 中央の実行(&self) -> Option<&一回の実行> {
        let mut 並び: Vec<&一回の実行> = self.実行一覧.iter().collect();
        並び.sort_by(|左, 右| 左.区間.群選択.p50ms.total_cmp(&右.区間.群選択.p50ms));
        並び.get(並び.len() / 2).copied()
    }
}

/// 群選択の走査が個体1件あたりに費やした時間。候補数は最終フレームの全個体数であり、p50は整定局面の値が支配する。
/// 常駐チャンク数が変わる往復局面の標本を含むため、この値は同じ物量点の実行間で比べるための指標であって絶対値の予算ではない。
pub(super) fn 個体あたりナノ秒(実行: &一回の実行) -> f64 {
    let 候補数 = 実行.計数.シーン.候補数;
    if 候補数 == 0 {
        return 0.0;
    }
    実行.区間.群選択.p50ms * 1_000_000.0 / 候補数を小数へ(候補数)
}

/// 候補数は最大でも数百万であり、f64の仮数53ビットで正確に表せる。
fn 候補数を小数へ(候補数: u64) -> f64 {
    let 分割 = u32::try_from(候補数 / 1_000).unwrap_or(u32::MAX);
    let 余り = u32::try_from(候補数 % 1_000).unwrap_or(0);
    f64::from(分割) * 1_000.0 + f64::from(余り)
}
