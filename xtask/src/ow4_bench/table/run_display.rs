//! 一回の計測が保持するCPU・GPU・計数・会計・プロセス一次値を欠かさず表示する。

use super::super::run::一回の実行;

pub(super) fn 一覧を表示する(実行一覧: &[一回の実行]) {
    for (番号, 実行) in 実行一覧.iter().enumerate() {
        println!("  実行{}:", 番号 + 1);
        区間を表示する("可視個体の選別", 実行.区間.可視個体の選別);
        区間を表示する("作業領域更新", 実行.区間.作業領域更新);
        区間を表示する("描画記録・送信・提示", 実行.区間.描画記録送信提示);
        println!(
            "    フェンス待機 p50 {:.4} / p99 {:.4} ms、フレーム間隔 p50 {:.4} / p99 {:.4} ms(参考値)",
            実行.区間.フェンス待機.p50ms, 実行.区間.フェンス待機.p99ms, 実行.区間.フレーム間隔.p50ms, 実行.区間.フレーム間隔.p99ms
        );
        println!(
            "    GPU シーン描画 {:.4} / シャドウ合計 {:.4} / 空の定常合計 {} / 定常合計 {:.4} ms / 更新時 {}",
            実行.gpu.シーン描画ミリ秒,
            実行.gpu.シャドウ合計ミリ秒,
            実行.gpu.空の定常合計ミリ秒.map_or_else(|| "空なし".to_string(), |値| format!("{値:.4}")),
            実行.gpu.定常合計ミリ秒,
            実行.gpu.更新時合計ミリ秒.map_or_else(|| "空なし".to_string(), |値| format!("{値:.4}"))
        );
        println!("    距離区分の世界メートル毎テクセル {:?}", 実行.世界メートル毎テクセル);
        super::counts::表示する(実行);
        会計を表示する(実行);
    }
}

fn 区間を表示する(名前: &str, 分布: super::super::measure::区間分布) {
    println!("    {名前} p50 {:.4} / p95 {:.4} / p99 {:.4} ms", 分布.p50ms, 分布.p95ms, 分布.p99ms);
}

fn 会計を表示する(実行: &一回の実行) {
    println!(
        "    台帳 最大RAM {} bytes / 最大VRAM {} bytes、読込{}件 {} bytes、解除{}件",
        実行.要約.最大ramバイト数, 実行.要約.最大vramバイト数, 実行.要約.ディスク読込件数, 実行.要約.ディスク読込バイト数, 実行.要約.gpu解除件数
    );
    println!(
        "    Vulkan確保 現在{} / 最大{}、デバイスバッファ {} bytes、ホストバッファ {} bytes",
        実行.確保.現在確保数, 実行.確保.最大同時確保数, 実行.確保.デバイスバッファ, 実行.確保.ホストバッファ
    );
    println!(
        "    プロセス最大 ワーキングセット {:.2} MiB / プライベート {:.2} MiB / 専用VRAM {}",
        実行.プロセス.ワーキングセットメビバイト,
        実行.プロセス.プライベートメビバイト,
        実行
            .プロセス
            .専用vramメビバイト
            .map_or_else(|| "取得不可".to_string(), |値| format!("{値:.2} MiB"))
    );
}
