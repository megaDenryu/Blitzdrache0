//! 実行1回ぶんの計器の計数を出す工程。受け取るのは1回の実行、出すのは発行数・段別個体数・投入頂点量の3行である。
//! 3つを1つの工程へまとめるのは、どれも同じフレームの同じ選別と発行から出た数であり、行を分けて読む理由が無いためである。

pub(super) fn 表示する(実行: &crate::ow4_bench::run::一回の実行) {
    println!(
        "    発行数 シーン{} / 距離区分別{:?}、候補数{}、シーン可視数{}、距離区分別の可視数{:?}、距離区分の和集合の可視数{}",
        実行.計数.シーン.発行数,
        実行.計数.距離区分別のシャドウ.iter().map(|発行| 発行.発行数).collect::<Vec<u64>>(),
        実行.計数.シーン.候補数,
        実行.計数.シーン.可視数,
        実行.計数.可視個体の選別.距離区分別の可視数,
        実行.計数.可視個体の選別.距離区分の和集合の可視数
    );
    println!(
        "    段別個体数 シーン{:?} / 距離区分別{:?}",
        実行.計数.シーン.段別個体数,
        実行
            .計数
            .距離区分別のシャドウ
            .iter()
            .map(|発行| 発行.段別個体数.clone())
            .collect::<Vec<Vec<u64>>>()
    );
    println!(
        "    投入頂点量 シーン{} / 距離区分別{:?}",
        実行.計数.シーン.投入頂点量,
        実行.計数.距離区分別のシャドウ.iter().map(|発行| 発行.投入頂点量).collect::<Vec<u64>>()
    );
}
