//! 物量点をまたいで並べる突き合わせの表を作る工程。受け取るのは物量点ごとの結果、出すのは1物量点につき1行である。
//! 実行ごとの一次値を出す側と分けているのは、こちらが「物量を上げたときに何が動いたか」に答える別の問いだからであり、
//! 触れるのも各物量点の中央の実行と個体あたり費用の幅だけに限られる。

use super::super::point::{個体あたりナノ秒, 物量点の結果};

pub(super) fn 表示する(結果一覧: &[物量点の結果]) {
    println!();
    println!("物量点の突き合わせ(各物量点の実行のうち中央の値、個体あたり費用は全実行の幅):");
    println!("  物量点 / 常駐個体数 / 群選択p50 / 群選択p99 / 作業領域更新p50 / 描画記録送信提示p50 / GPUシーン / GPUシャドウ / 群選択の個体あたり");
    for 結果 in 結果一覧 {
        一行を表示する(結果);
    }
}

fn 一行を表示する(結果: &物量点の結果) {
    let (Some(中央), Some(幅)) = (結果.中央の実行(), 個体あたりナノ秒の幅(結果)) else {
        println!("  {}: 実行が1つも成功していない", 結果.名前);
        return;
    };
    println!(
        "  {} / {} / {:.4} / {:.4} / {:.4} / {:.4} / {:.4} / {:.4} / {:.2}〜{:.2} ns",
        結果.名前,
        中央.計数.シーン.候補数,
        中央.区間.群選択.p50ms,
        中央.区間.群選択.p99ms,
        中央.区間.作業領域更新.p50ms,
        中央.区間.描画記録送信提示.p50ms,
        中央.gpu.シーン描画ms,
        中央.gpu.シャドウms,
        幅.0,
        幅.1
    );
}

/// 同じ物量点の実行間で個体あたり費用がどこまで振れたか。折れ点の判定はこの幅を実行間ノイズ帯として使う。
fn 個体あたりナノ秒の幅(結果: &物量点の結果) -> Option<(f64, f64)> {
    let 一覧: Vec<f64> = 結果.実行一覧.iter().map(個体あたりナノ秒).collect();
    let 最小 = 一覧.iter().copied().min_by(f64::total_cmp)?;
    let 最大 = 一覧.iter().copied().max_by(f64::total_cmp)?;
    Some((最小, 最大))
}
