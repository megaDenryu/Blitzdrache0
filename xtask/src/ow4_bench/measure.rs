//! 1回の実行の終了時報告から、物量計測が見る計器を取り出す工程。受け取るのは終了時報告、返すのはCPU区間・Vulkan確保・
//! 世界メートル毎テクセルである。計数とストリーミング要約は既存の読み取りがあり、GPU時間の表は`gpu_table`が持つ。
//! 区間名の綴りは`crates/blitz_app/src/reports.rs`の出力と一致させている。

use crate::acceptance::{報告の区画, 報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

/// 1つのCPU区間の分布。物量点をまたいで比べるのはp50・p95・p99であり、平均は外れ値に引きずられるため補助に留める。
#[derive(Clone, Copy)]
pub(super) struct 区間分布 {
    pub(super) p50ms: f64,
    pub(super) p95ms: f64,
    pub(super) p99ms: f64,
}

pub(super) struct CPU区間一式 {
    pub(super) 可視個体の選別: 区間分布,
    pub(super) 作業領域更新: 区間分布,
    pub(super) 描画記録送信提示: 区間分布,
    pub(super) フェンス待機: 区間分布,
    /// FIFO提示待ちを含むフレーム開始間隔。支配要因の判定には使わず、参考値として残す。
    pub(super) フレーム間隔: 区間分布,
}

pub(super) struct Vulkan確保 {
    pub(super) 現在確保数: u64,
    pub(super) 最大同時確保数: u64,
    pub(super) デバイスバッファ: u64,
    pub(super) ホストバッファ: u64,
}

pub(super) fn cpu区間を取り出す(報告: &終了時報告) -> Result<CPU区間一式, 検収エラー> {
    let レンダラー区画 = 報告.見出しの区画(見出しを組む("レンダラーCPU区間"))?;
    let インスタンス区画 = 報告.見出しの区画(見出しを組む("インスタンスCPU区間"))?;
    let 間隔区画 = 報告.見出しの区画(見出しを組む("CPU側フレーム間隔"))?;
    Ok(CPU区間一式 {
        可視個体の選別: 分布を読む(接頭辞の行(&インスタンス区画, "可視個体の選別")?, "")?,
        作業領域更新: 分布を読む(接頭辞の行(&レンダラー区画, "作業領域更新:")?, "")?,
        描画記録送信提示: 分布を読む(接頭辞の行(&レンダラー区画, "描画記録・送信・提示:")?, "")?,
        フェンス待機: 分布を読む(接頭辞の行(&レンダラー区画, "フェンス待機:")?, "")?,
        フレーム間隔: 区間分布 {
            p50ms: 分位を読む(接頭辞の行(&間隔区画, "p50:")?, "p50:")?,
            p95ms: 分位を読む(接頭辞の行(&間隔区画, "p95:")?, "p95:")?,
            p99ms: 分位を読む(接頭辞の行(&間隔区画, "p99:")?, "p99:")?,
        },
    })
}

/// 最終フレームの判定が使った距離区分ごとの世界メートル毎テクセル。シャドウマップの1テクセルが世界で覆う長さであり、
/// 4距離区分の解像度密度そのものである(参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「予算」)。
pub(super) fn 世界メートル毎テクセルを取り出す(報告: &終了時報告) -> Result<Vec<f64>, 検収エラー> {
    let 区画 = 報告.見出しの区画(見出しを組む("描画発行内訳"))?;
    接頭辞の行(&区画, "距離区分の世界メートル毎テクセル:")?
        .見出しに続く添字順の数一覧(&見出しを組む("距離区分の世界メートル毎テクセル:"))
}

pub(super) fn vulkan確保を取り出す(報告: &終了時報告) -> Result<Vulkan確保, 検収エラー> {
    let 区画 = 報告.見出しの区画(見出しを組む("Vulkanメモリ確保"))?;
    let 用途 = 報告.見出しの区画(見出しを組む("用途別現在量:"))?;
    Ok(Vulkan確保 {
        現在確保数: 整数を読む(&区画, "現在確保数:")?,
        最大同時確保数: 整数を読む(&区画, "最大同時確保数:")?,
        デバイスバッファ: 整数を読む(&用途, "デバイスバッファ:")?,
        ホストバッファ: 整数を読む(&用途, "ホストバッファ:")?,
    })
}

fn 分布を読む(行: &報告の行, 分位の接尾辞: &str) -> Result<区間分布, 検収エラー> {
    Ok(区間分布 {
        p50ms: 分位を読む(行, &format!("p50{分位の接尾辞}"))?,
        p95ms: 分位を読む(行, &format!("p95{分位の接尾辞}"))?,
        p99ms: 分位を読む(行, &format!("p99{分位の接尾辞}"))?,
    })
}

fn 分位を読む(行: &報告の行, 鍵の綴り: &str) -> Result<f64, 検収エラー> {
    行.鍵に結ばれた数(&鍵を組む(鍵の綴り), 鍵に値が結ばれる形::次の語が値である)
}

fn 整数を読む(区画: &報告の区画, 鍵の綴り: &'static str) -> Result<u64, 検収エラー> {
    接頭辞の行(区画, 鍵の綴り)?.鍵に結ばれた語から数字だけを読む(&鍵を組む(鍵の綴り), 鍵に値が結ばれる形::次の語が値である)
}

fn 接頭辞の行<'区画>(区画: &'区画 報告の区画, 接頭辞: &str) -> Result<&'区画 報告の行, 検収エラー> {
    区画.接頭辞の行(&見出しを組む(接頭辞))
}

fn 見出しを組む(綴り: &str) -> 報告の見出し {
    報告の見出し::組み立てた綴りから生成する(綴り.to_string())
}

fn 鍵を組む(綴り: &str) -> 報告の行の鍵 {
    報告の行の鍵::組み立てた綴りから生成する(綴り.to_string())
}
