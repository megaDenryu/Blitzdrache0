//! 1回の実行の標準出力から、物量計測が見る計器を取り出す工程。受け取るのは標準出力、返すのはCPU区間・GPU時間・
//! Vulkan確保・フレーム間隔の4つである。計数とストリーミング要約は既存の読み取りがあるためここでは扱わない。
//! 区間名の綴りは`crates/blitz_app/src/reports.rs`の出力と一致させている。

use super::section_parse::{区画の行, 区画の行一覧, 鍵の次の小数, 鍵の次の整数};

/// 1つのCPU区間の分布。物量点をまたいで比べるのはp50・p95・p99であり、平均は外れ値に引きずられるため補助に留める。
#[derive(Clone, Copy)]
pub(super) struct 区間分布 {
    pub(super) p50ms: f64,
    pub(super) p95ms: f64,
    pub(super) p99ms: f64,
}

pub(super) struct CPU区間一式 {
    pub(super) 可視個体の選別: 区間分布,
    pub(super) 作業領域更新: 区間分布,
    pub(super) 描画記録送信提示: 区間分布,
    pub(super) フェンス待機: 区間分布,
    /// FIFO提示待ちを含むフレーム開始間隔。支配要因の判定には使わず、参考値として残す。
    pub(super) フレーム間隔: 区間分布,
}

pub(super) struct GPU時間 {
    pub(super) シーン描画ms: f64,
    pub(super) シャドウms: f64,
}

pub(super) struct Vulkan確保 {
    pub(super) 現在確保数: u64,
    pub(super) 最大同時確保数: u64,
    pub(super) デバイスバッファ: u64,
    pub(super) ホストバッファ: u64,
}

pub(super) fn cpu区間を取り出す(標準出力: &str) -> Result<CPU区間一式, String> {
    let レンダラー区画 = 区画の行一覧(標準出力, "レンダラーCPU区間")?;
    let インスタンス区画 = 区画の行一覧(標準出力, "インスタンスCPU区間")?;
    let 間隔区画 = 区画の行一覧(標準出力, "CPU側フレーム間隔")?;
    Ok(CPU区間一式 {
        可視個体の選別: 分布を読む(区画の行(&インスタンス区画, "可視個体の選別")?)?,
        作業領域更新: 分布を読む(区画の行(&レンダラー区画, "作業領域更新:")?)?,
        描画記録送信提示: 分布を読む(区画の行(&レンダラー区画, "描画記録・送信・提示:")?)?,
        フェンス待機: 分布を読む(区画の行(&レンダラー区画, "フェンス待機:")?)?,
        フレーム間隔: 区間分布 {
            p50ms: 鍵の次の小数(区画の行(&間隔区画, "p50:")?, "p50:")?,
            p95ms: 鍵の次の小数(区画の行(&間隔区画, "p95:")?, "p95:")?,
            p99ms: 鍵の次の小数(区画の行(&間隔区画, "p99:")?, "p99:")?,
        },
    })
}

pub(super) fn gpu時間を取り出す(標準出力: &str) -> Result<GPU時間, String> {
    let 区画 = 区画の行一覧(標準出力, "パス別GPU時間")?;
    Ok(GPU時間 {
        シーン描画ms: 鍵の次の小数(区画の行(&区画, "シーン描画:")?, "シーン描画:")?,
        // 4距離区分CSM(第5段)以降、シャドウは距離区分ごとの行に分かれ、合計だけを別行「シャドウ合計」が持つ
        // (参照: `crates/blitz_app/src/reports.rs`のgpu時間表を表示する、設計文書「予算」)。
        シャドウms: 鍵の次の小数(区画の行(&区画, "シャドウ合計:")?, "シャドウ合計:")?,
    })
}

pub(super) fn vulkan確保を取り出す(標準出力: &str) -> Result<Vulkan確保, String> {
    let 区画 = 区画の行一覧(標準出力, "Vulkanメモリ確保")?;
    let 用途 = 区画の行一覧(標準出力, "用途別現在量:")?;
    Ok(Vulkan確保 {
        現在確保数: 鍵の次の整数(区画の行(&区画, "現在確保数:")?, "現在確保数:")?,
        最大同時確保数: 鍵の次の整数(区画の行(&区画, "最大同時確保数:")?, "最大同時確保数:")?,
        デバイスバッファ: 鍵の次の整数(区画の行(&用途, "デバイスバッファ:")?, "デバイスバッファ:")?,
        ホストバッファ: 鍵の次の整数(区画の行(&用途, "ホストバッファ:")?, "ホストバッファ:")?,
    })
}

fn 分布を読む(行: &str) -> Result<区間分布, String> {
    Ok(区間分布 {
        p50ms: 鍵の次の小数(行, "p50")?,
        p95ms: 鍵の次の小数(行, "p95")?,
        p99ms: 鍵の次の小数(行, "p99")?,
    })
}
