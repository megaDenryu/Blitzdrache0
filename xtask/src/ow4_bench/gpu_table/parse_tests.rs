//! 表の読み取りと合計の導出の検査。担当するのは「どの行が定常合計へ入りどの行が入らないか」を標本で固定することである。
//! 更新時の2区間を除くことと導出の行を二重に足さないことは、表を見ただけでは判らないため負の対照として並べる。

#![allow(clippy::unwrap_used)]

use super::取り出す;

const 空あり: &str = "パス別GPU時間(移動平均、60フレーム窓):\n  シーン描画: 1.0000 ms\n  シャドウ距離区分0: 0.5000 ms\n  シャドウ距離区分1: 0.2500 ms\n  透過率生成: 0.1300 ms\n  多重散乱生成: 0.5500 ms\n  スカイビュー生成: 0.0200 ms\n  空中遠近生成: 0.0300 ms\n  空中遠近合成: 0.0200 ms\n  空: 0.0100 ms\n  シャドウ合計: 0.7500 ms\n";
const 空なし: &str = "パス別GPU時間:\n  シーン描画: 1.0 ms\n  シャドウ距離区分0: 0.5 ms\n  シャドウ合計: 0.5 ms\n";

/// 定常合計は距離区分ごとの行を足し、導出である「シャドウ合計」の行も更新時の2区間も足さない。
#[test]
fn 定常合計は導出の行と更新時の区間を除く() {
    let 時間 = 取り出す(空あり).unwrap();
    assert!((時間.定常合計ms - 1.83).abs() < 1.0e-9, "{}", 時間.定常合計ms);
    assert!((時間.シャドウ合計ms - 0.75).abs() < 1.0e-9);
    assert!((時間.空の定常合計ms.unwrap() - 0.08).abs() < 1.0e-9);
    assert!((時間.更新時合計ms.unwrap() - 0.68).abs() < 1.0e-9);
}

/// 空を描かない条件は空の不在を返し、0ミリ秒とは区別する。
#[test]
fn 空の区間が1本も無ければ不在を返す() {
    let 時間 = 取り出す(空なし).unwrap();
    assert_eq!(時間.空の定常合計ms, None);
    assert_eq!(時間.更新時合計ms, None);
    assert!((時間.定常合計ms - 1.5).abs() < 1.0e-9, "{}", 時間.定常合計ms);
}

#[test]
fn 空の区間が一部しか無ければ失敗にする() {
    let 一部 = "パス別GPU時間:\n  シーン描画: 1.0 ms\n  空: 0.01 ms\n  シャドウ合計: 0.5 ms\n";
    assert!(取り出す(一部).is_err());
}
