//! パス別GPU時間の表から、予算と突き合わせる量を導く工程。受け取るのは終了時報告、返すのはシーン描画・シャドウ合計・
//! 空の定常合計・定常合計・更新時合計である。表の綴りは`crates/blitz_app/src/reports.rs`の出力と一致させている。
//! 定常合計から「シャドウ合計」の行を除くのは、その行が距離区分ごとの4行から導いた重複であり足すと二重計上になるためである。
//! 透過率生成と多重散乱生成を除くのは、その2区間が大気の変わったフレームだけ走る更新時の量だからである。
//! 区間の台帳は`sky-lut`が持つものをそのまま読む(同じ集合を2箇所で決めない)。

#[cfg(test)]
mod parse_tests;

use crate::acceptance::{判定の名前, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};
use crate::sky_lut::gpu_time::{定常の区間一覧, 更新時の区間一覧};

const 見出し: 報告の見出し = 報告の見出し::定数から生成する("パス別GPU時間");
const シーン描画の区間名: &str = "シーン描画";
const シャドウ合計の区間名: &str = "シャドウ合計";

/// `空の定常合計ms`と`更新時合計ms`が`Option`なのは、空を描かない条件では該当区間が1本も立たないためである。
/// 0を返すと「空が速い」と読めてしまうため、不在は`None`で表し値を偽装しない。
pub(super) struct GPU時間 {
    pub(super) シーン描画ms: f64,
    pub(super) シャドウ合計ms: f64,
    pub(super) 空の定常合計ms: Option<f64>, // 空を描かない条件では`None`
    pub(super) 定常合計ms: f64,             // 毎フレーム走る区間だけの合計。60fpsの1フレームと比べる値である
    pub(super) 更新時合計ms: Option<f64>,   // 大気が変わったフレームだけ走る2区間の合計。空を描かない条件では`None`
}

pub(super) fn 取り出す(報告: &終了時報告) -> Result<GPU時間, 検収エラー> {
    let 表 = 表を読む(報告)?;
    let 定常 = 表.iter().filter(|(名前, _)| 定常合計へ入れるか(名前));
    Ok(GPU時間 {
        シーン描画ms: 区間を参照する(&表, シーン描画の区間名)?,
        シャドウ合計ms: 区間を参照する(&表, シャドウ合計の区間名)?,
        空の定常合計ms: 区間群の合計(&表, &定常の区間一覧)?,
        定常合計ms: 定常.map(|(_, ミリ秒)| *ミリ秒).sum(),
        更新時合計ms: 区間群の合計(&表, &更新時の区間一覧)?,
    })
}

fn 定常合計へ入れるか(名前: &str) -> bool {
    名前 != シャドウ合計の区間名 && !更新時の区間一覧.contains(&名前)
}

/// 表の行を「区間名とミリ秒」の対の並びへ写す。区間名は行の頭から最初の`:`までであり、
/// 区間の集合は実行の構成で変わるため、名前を型で数え上げず表として持つ。
fn 表を読む(報告: &終了時報告) -> Result<Vec<(String, f64)>, 検収エラー> {
    let mut 表 = Vec::new();
    for 行 in 報告.見出しの区画(見出し)?.行一覧() {
        let Some((名前, _)) = 行.原文().trim_start().split_once(':') else {
            continue;
        };
        let 鍵 = 報告の行の鍵::組み立てた綴りから生成する(format!("{名前}:"));
        表.push((名前.to_string(), 行.鍵に結ばれた数(&鍵, 鍵に値が結ばれる形::次の語が値である)?));
    }
    Ok(表)
}

fn 区間を参照する(表: &[(String, f64)], 区間名: &str) -> Result<f64, 検収エラー> {
    表.iter()
        .find(|(名前, _)| 名前 == 区間名)
        .map(|(_, ミリ秒)| *ミリ秒)
        .ok_or_else(|| 区間の判定名(区間名).あるはずのものが無い破れ().into())
}

/// 名前で挙げた区間の合計。そろって立つか1本も立たないかのどちらかであり、一部だけ立つのは構成が想定と
/// 違うことを意味するため、残りを0として足さず失敗にする。
fn 区間群の合計(表: &[(String, f64)], 名前一覧: &[&str]) -> Result<Option<f64>, 検収エラー> {
    let 値一覧: Vec<Option<f64>> = 名前一覧.iter().map(|区間名| 区間を参照する(表, 区間名).ok()).collect();
    let 立った本数 = 値一覧.iter().filter(|値| 値.is_some()).count();
    if 立った本数 == 0 {
        return Ok(None);
    }
    一括で立つ区間の判定名(名前一覧).一致を課す(立った本数, 名前一覧.len())?;
    Ok(Some(値一覧.into_iter().flatten().sum()))
}

fn 一括で立つ区間の判定名(名前一覧: &[&str]) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{見出し}の表で一括で立つはずの区間{名前一覧:?}のうち立った本数"))
}

fn 区間の判定名(区間名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{見出し}の表の区間{区間名}"))
}
