//! 反復の代表値の採り方の検査。担当するのは「3回の実行から採る値が最小でも最大でもないこと」と
//! 「標本が無いときに0でなく不在を返すこと」を固定することである。

#![allow(clippy::unwrap_used)]

use super::中央を採る;

#[test]
fn 中央は最小でも最大でもない値を採る() {
    assert!((中央を採る(&[3.0, 1.0, 2.0]).unwrap() - 2.0).abs() < 1.0e-9);
}

/// 標本が無い実行を0ミリ秒として予算内と告げないため、不在をそのまま返す。
#[test]
fn 標本が無ければ中央は不在である() {
    assert_eq!(中央を採る(&[]), None);
}
