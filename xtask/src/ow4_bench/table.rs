//! 実行1回ぶんの一次値を人間が読める形で出す工程。受け取るのは物量点ごとの実行一覧、出すのは標準出力への行だけである。
//! 折れ点の裁定は行わない。判定に要るのは区間の値と個体あたり費用そのものであり、ここが要約すると一次値が失われる。
//! 物量点をまたいだ突き合わせは`comparison`にある。

mod comparison;

use super::point::物量点の結果;

pub(super) fn 表示する(結果一覧: &[物量点の結果]) {
    for 結果 in 結果一覧 {
        実行ごとを表示する(結果);
    }
    comparison::表示する(結果一覧);
}

fn 実行ごとを表示する(結果: &物量点の結果) {
    println!();
    println!(
        "物量点{}: チャンクあたり{}体、最終フレームの常駐個体数{}体",
        結果.名前,
        結果.チャンクあたり個体数,
        結果.実行一覧.first().map_or(0, |実行| 実行.計数.シーン.候補数)
    );
    for (番号, 実行) in 結果.実行一覧.iter().enumerate() {
        println!("  実行{}:", 番号 + 1);
        println!(
            "    群選択 p50 {:.4} / p95 {:.4} / p99 {:.4} ms",
            実行.区間.群選択.p50ms, 実行.区間.群選択.p95ms, 実行.区間.群選択.p99ms
        );
        println!(
            "    作業領域更新 p50 {:.4} / p95 {:.4} / p99 {:.4} ms",
            実行.区間.作業領域更新.p50ms, 実行.区間.作業領域更新.p95ms, 実行.区間.作業領域更新.p99ms
        );
        println!(
            "    描画記録・送信・提示 p50 {:.4} / p95 {:.4} / p99 {:.4} ms",
            実行.区間.描画記録送信提示.p50ms, 実行.区間.描画記録送信提示.p95ms, 実行.区間.描画記録送信提示.p99ms
        );
        println!(
            "    フェンス待機 p50 {:.4} / p99 {:.4} ms、フレーム間隔 p50 {:.4} / p99 {:.4} ms(参考値)",
            実行.区間.フェンス待機.p50ms, 実行.区間.フェンス待機.p99ms, 実行.区間.フレーム間隔.p50ms, 実行.区間.フレーム間隔.p99ms
        );
        println!("    GPU シーン描画 {:.4} / シャドウ {:.4} ms", 実行.gpu.シーン描画ms, 実行.gpu.シャドウms);
        計数を表示する(実行);
        会計を表示する(実行);
    }
}

fn 計数を表示する(実行: &super::run::一回の実行) {
    println!(
        "    発行数 シーン{} / シャドウ{}、候補数{}、シーン可視数{}、段別個体数 シーン{:?} シャドウ{:?}",
        実行.計数.シーン.発行数,
        実行.計数.シャドウ.発行数,
        実行.計数.シーン.候補数,
        実行.計数.シーン.可視数,
        実行.計数.シーン.段別個体数,
        実行.計数.シャドウ.段別個体数
    );
}

fn 会計を表示する(実行: &super::run::一回の実行) {
    println!(
        "    台帳 最大RAM {} bytes / 最大VRAM {} bytes、読込{}件 {} bytes、解除{}件",
        実行.要約.最大ramバイト数, 実行.要約.最大vramバイト数, 実行.要約.ディスク読込件数, 実行.要約.ディスク読込バイト数, 実行.要約.gpu解除件数
    );
    println!(
        "    Vulkan確保 現在{} / 最大{}、デバイスバッファ {} bytes、ホストバッファ {} bytes",
        実行.確保.現在確保数, 実行.確保.最大同時確保数, 実行.確保.デバイスバッファ, 実行.確保.ホストバッファ
    );
    println!(
        "    プロセス最大 ワーキングセット {:.2} MiB / プライベート {:.2} MiB / 専用VRAM {}",
        実行.プロセス.ワーキングセットmib,
        実行.プロセス.プライベートmib,
        実行
            .プロセス
            .専用vrammib
            .map_or_else(|| "取得不可".to_string(), |値| format!("{値:.2} MiB"))
    );
}
