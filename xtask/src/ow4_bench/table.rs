//! 実行1回ぶんの一次値を人間が読める形で出す工程。受け取るのは物量点ごとの実行一覧、出すのは標準出力への行だけである。
//! 折れ点の裁定は行わない。判定に要るのは区間の値と個体あたり費用そのものであり、ここが要約すると一次値が失われる。
//! 物量点をまたいだ突き合わせは`comparison`にある。

mod comparison;
mod counts;
mod run_display;

use super::point::物量点の結果;

pub(super) fn 表示する(結果一覧: &[物量点の結果]) {
    for 結果 in 結果一覧 {
        実行ごとを表示する(結果);
    }
    comparison::表示する(結果一覧);
}

pub(super) fn 大規模世界を表示する(検査候補数: u64, 実行一覧: &[super::run::一回の実行]) {
    println!("\n大規模世界: validation検査候補数{検査候補数}、反復{}回", 実行一覧.len());
    run_display::一覧を表示する(実行一覧);
}

fn 実行ごとを表示する(結果: &物量点の結果) {
    println!();
    println!(
        "物量点{}: チャンクあたり{}体、最終フレームの常駐個体数{}体、validation検査を通した候補数{}体",
        結果.名前,
        結果.チャンクあたり個体数,
        結果.実行一覧.first().map_or(0, |実行| 実行.計数.シーン.候補数),
        結果.検査候補数
    );
    run_display::一覧を表示する(&結果.実行一覧);
}
