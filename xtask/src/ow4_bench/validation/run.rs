//! 型付き起動指定をデバッグビルドで走らせ、validationと候補数を読む共通工程。

use std::path::Path;

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 世界を読ませて報告を採る実行環境, 判定の名前, 実行時アセットルート, 描画フレーム数, 検収の実行名, 終了時報告,
};

use super::super::error::物量計測エラー;

const 検証層の指摘: 判定の名前 = 判定の名前::定数から生成する("計測のデバッグ実行のvalidation指摘");

pub(in crate::ow4_bench) fn 起動指定で検査する(
    アセットルート: &Path,
    実行名: 検収の実行名,
    フレーム数: 描画フレーム数,
    起動指定: &アプリの起動指定,
) -> Result<u64, 物量計測エラー> {
    println!("[xtask] {}をデバッグビルドでvalidation検査", アセットルート.display());
    let 環境 = 世界を読ませて報告を採る実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::パスから生成する(アセットルート.to_path_buf()),
    );
    let 報告 = 環境.報告を採る(実行名, 起動指定)?;
    出どころを付けて流す(&報告, フレーム数);
    let 計数 = crate::report_parse::取り出す(&報告)?;
    検証層の指摘.零件であることを課す(計数.validation件数)?;
    Ok(計数.シーン.候補数)
}

fn 出どころを付けて流す(報告: &終了時報告, フレーム数: 描画フレーム数) {
    for 行 in 報告.本文().lines() {
        println!("[validation検査 {}フレーム] {行}", フレーム数.枚数());
    }
}
