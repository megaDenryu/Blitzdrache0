//! 1回の実行へ渡す起動指定のうち、物量以外で変わりうるものを保つ型と、その引数の読み取りと起動指定への写し。
//! 物量(チャンクあたり個体数)を同じ型へ入れないのは、物量が物量点ごとに変わるのに対し、ここが持つ2つが
//! 全物量点で共有される条件だからである。既定を従来条件に置くのは、この計測が2026-07-29から続く時系列であり、
//! 指定なしの実行が過去の値と比べられる必要があるためである(参照: `_doc/計測/OW4_2026-07-29.md`)。

#[cfg(test)]
mod argument_tests;

use super::error::物量計測エラー;

/// 一日内時刻を渡す引数の綴り。破れの文面が打ち直す語をそのまま名指す。
const 一日内時刻の引数名: &str = "--time-of-day";
/// 物量点として渡された語の役目。数として読めなかったときの文面がこの名前で語を名指す。
const 物量点の引数名: &str = "チャンクあたり個体数";

/// 何を描くかの条件。予算のどの行を判定できるかがこの選択で決まる。
///
/// `素の描画`はライティング・ポスト処理・空を止めた素の描画で、シーン描画とシャドウの2行だけを過去の記録と比べられる。
/// `本番の描画`は起動指定を1つも足さない本番の描画で、空とポスト処理を含むため空1.0msとGPU合計16.6msを判定できる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 描画条件 {
    素の描画,   // シーン描画とシャドウの2行だけを過去の記録と比べる
    本番の描画, // 空1.0msとGPU合計16.6msを含めて判定する
}

pub(super) struct 計測条件 {
    pub(super) 描画: 描画条件,
    pub(super) 一日内時刻の秒: Option<u32>, // `--time-of-day <秒>`へ渡す。`None`なら世界の方針の既定時刻のまま
    pub(super) シャドウ: super::shadow_condition::シャドウ計測指定, // 律速切り分けで振る軸。指定が無ければ起動指定の語を1つも足さない
}

pub(super) struct 引数の読み {
    pub(super) 物量点一覧: Vec<usize>, // チャンクあたり個体数の列。空なら呼び出し元が既定の3点を使う
    pub(super) 条件: 計測条件,
}

pub(super) fn 引数を読む(引数一覧: &[String]) -> Result<引数の読み, 物量計測エラー> {
    let mut 物量点一覧 = Vec::new();
    let mut 描画 = 描画条件::素の描画;
    let mut 一日内時刻の秒 = None;
    let mut シャドウ = super::shadow_condition::シャドウ計測指定::default();
    let mut 残り = 引数一覧.iter();
    while let Some(語) = 残り.next() {
        if シャドウ.語を読む(語.as_str(), &mut 残り)? {
            continue;
        }
        // 注意: 一日内時刻の引数名は定数であり、この枝は綴りの一致で選ばれる。束縛でないことを保つため、
        // この名前を変数へ変えてはならない(変えるとこの枝が全部の語を受け、続く枝へ1語も届かない)。
        match 語.as_str() {
            "--production-draw" => 描画 = 描画条件::本番の描画,
            一日内時刻の引数名 => 一日内時刻の秒 = Some(一日内秒を読む(残り.next())?),
            _ => 物量点一覧.push(個体数を読む(語)?),
        }
    }
    Ok(引数の読み {
        物量点一覧,
        条件: 計測条件 {
            描画,
            一日内時刻の秒,
            シャドウ,
        },
    })
}

/// 描画条件を起動指定へ写す。地形世界は空を持つ方針であるため、従来条件を保つには空とライティングとポスト処理を明示的に外す。
pub(super) fn 描画の起動指定(描画: 描画条件) -> &'static [&'static str] {
    match 描画 {
        描画条件::素の描画 => &["--unlit", "--no-post", "--no-sky"],
        描画条件::本番の描画 => &[],
    }
}

/// 時刻の起動指定。計測本体とvalidation検査の両方が同じ語を渡すため、作る場所を1つにする。
pub(super) fn 時刻の起動指定(条件: &計測条件) -> Vec<String> {
    let Some(秒) = 条件.一日内時刻の秒 else { return Vec::new() };
    vec!["--time-of-day".to_string(), 秒.to_string()]
}

fn 一日内秒を読む(語: Option<&String>) -> Result<u32, 物量計測エラー> {
    let 語 = 語.ok_or(物量計測エラー::引数の次に値が無い {
        引数名: 一日内時刻の引数名
    })?;
    語.parse().map_err(|_| 物量計測エラー::引数の値を数として読めない {
        引数名: 一日内時刻の引数名,
        語: 語.clone(),
    })
}

fn 個体数を読む(語: &str) -> Result<usize, 物量計測エラー> {
    match 語.parse::<usize>() {
        Ok(個体数) if 個体数 > 0 => Ok(個体数),
        Ok(_) => Err(物量計測エラー::チャンクあたり個体数が零である),
        Err(_) => Err(物量計測エラー::引数の値を数として読めない {
            引数名: 物量点の引数名,
            語: 語.to_string(),
        }),
    }
}
