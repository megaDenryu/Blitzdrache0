//! 物量計測が返す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。
//! 様式は`acceptance/error.rs`と`depth_prepass_cost/error.rs`に倣う。
//!
//! 検収の器の破れを枝で内包するのは、この入口が起動と報告の読み取りを一続きに通すためである。
//! 折れ点の裁定は人が記録を読んで行うため、判定の破れの枝はvalidationの残りだけである。
//!
//! 引数の解釈と支度とファイルの書き出しをここが持つのは、どれも報告の読み取りではないためである。
//! 人が読む1文へ写すのは`display`が持つ。

mod display;

use std::path::PathBuf;

use crate::acceptance::{判定の破れ, 検収エラー};
use crate::release_build::計測用の構築の破れ;
use crate::shader_copy::シェーダーの一時コピーの破れ;

#[derive(Debug)]
pub(super) enum 物量計測エラー {
    検収の器が破れた(検収エラー),
    判定が破れた(判定の破れ),
    計測用の構築が失敗した(計測用の構築の破れ),
    シェーダーの一時コピーを作れなかった(シェーダーの一時コピーの破れ),
    引数の次に値が無い {
        引数名: &'static str,
    },
    引数の値を数として読めない {
        引数名: &'static str,
        語: String,
    },
    /// 個体が1体も無い物量点は、物量を振ったことにならない。
    チャンクあたり個体数が零である,
    検証用ソースアセットを生成できなかった,
    物量点の実行時アセットを生成できなかった {
        チャンクあたり個体数: usize,
    },
    出力先を作れなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    実行の標準出力を読めなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    /// 採取が1標本も採れないまま終わった実行。プロセスの実測が空のまま表へ載ると、載っていない値を読むことになる。
    実行が標本を1つも採れなかった {
        名前: String,
    },
}

impl std::error::Error for 物量計測エラー {}

impl From<検収エラー> for 物量計測エラー {
    fn from(破れ: 検収エラー) -> Self {
        Self::検収の器が破れた(破れ)
    }
}

impl From<判定の破れ> for 物量計測エラー {
    fn from(破れ: 判定の破れ) -> Self {
        Self::判定が破れた(破れ)
    }
}
