//! 4つの予算との突き合わせ。受け取るのは物量点ごとの結果、出すのは物量点ごとの判定の行だけである。
//! 予算を破った項目は語で示し、消費率も実測値も隠さない。反復の代表値に中央値を採るのは、実行間の振れの
//! 最小でも最大でもない値で判定するためである(`table`の中央の実行と同じ流儀)。
//! 参照: `_doc/計画/評価軸.md`「3.1 フレーム予算との比較」「3.6 CPU区間予算」、`_doc/設計/空と時間帯と遠距離シャドウ.md`「予算」

#[cfg(test)]
mod median_tests;

use super::point::物量点の結果;
use super::run::一回の実行;

/// 4距離区分の合計に対するシャドウの予算。距離区分ごとに2.6msではない。
/// 2026-08-03のオーナー裁定で2.0msから改定した(最大影距離225メートルの実測2.4842msへ環境の揺れの余裕を足した値)。
const シャドウ合計の予算ミリ秒: f64 = 2.6;
/// 可視個体の選別のCPU区間予算(OW4制定、暫定)。
const 可視個体の選別の予算ミリ秒: f64 = 2.0;
/// 60fpsの1フレーム。毎フレーム走る区間の合計をこれと比べる。
const GPU定常合計の予算ミリ秒: f64 = 16.6;

/// 1つの予算項目。表示名と、実行1回からその量を読む関数と、予算の3つで1つの判定が決まる。
type 予算項目 = (&'static str, fn(&一回の実行) -> f64, f64);

pub(super) fn 表示する(結果一覧: &[物量点の結果]) {
    for 結果 in 結果一覧 {
        println!();
        println!("物量点{}の予算判定({}回の中央値):", 結果.名前, 結果.実行一覧.len());
        空を表示する(&結果.実行一覧);
        let 項目一覧: [予算項目; 3] = [
            ("シャドウ合計(GPU)", |実行| 実行.gpu.シャドウ合計ms, シャドウ合計の予算ミリ秒),
            (
                "可視個体の選別(CPU p50)",
                |実行| 実行.区間.可視個体の選別.p50ms,
                可視個体の選別の予算ミリ秒,
            ),
            ("GPU定常合計", |実行| 実行.gpu.定常合計ms, GPU定常合計の予算ミリ秒),
        ];
        for (名前, 読む, 予算) in 項目一覧 {
            一項目を表示する(名前, 中央値(&結果.実行一覧, 読む), 予算);
        }
        更新時を表示する(&結果.実行一覧);
        世界メートル毎テクセルを表示する(&結果.実行一覧);
    }
}

/// 空を描かない条件では区間が1本も立たないため、0ミリ秒として予算内と告げず、測っていないことを語で出す。
fn 空を表示する(実行一覧: &[一回の実行]) {
    let 一覧: Vec<f64> = 実行一覧.iter().filter_map(|実行| 実行.gpu.空の定常合計ms).collect();
    match 中央を採る(&一覧) {
        Some(値) => 一項目を表示する("空の定常合計(GPU)", Some(値), crate::sky_lut::gpu_time::空の定常予算ミリ秒),
        None => println!("  空の定常合計(GPU): 空を描かない条件のため測っていない"),
    }
}

fn 一項目を表示する(名前: &str, 実測ミリ秒: Option<f64>, 予算ミリ秒: f64) {
    let Some(実測) = 実測ミリ秒 else {
        println!("  {名前}: 実行が1つも成功していない");
        return;
    };
    let 判定 = if 実測 <= 予算ミリ秒 { "予算内" } else { "予算超過" };
    println!(
        "  {名前}: {実測:.4} ms / 予算 {予算ミリ秒:.1} ms = {:.1}% {判定}",
        実測 * 100.0 / 予算ミリ秒
    );
}

/// 大気が変わったフレームだけ走る2区間。定常合計へ混ぜないため、予算の判定を付けず値だけを別に出す。
fn 更新時を表示する(実行一覧: &[一回の実行]) {
    let 一覧: Vec<f64> = 実行一覧.iter().filter_map(|実行| 実行.gpu.更新時合計ms).collect();
    let 語 = 中央を採る(&一覧).map_or_else(|| "空を描かない条件のため測っていない".to_string(), |値| format!("{値:.4} ms"));
    println!("  更新時の2区間(GPU、定常合計に含めない): {語}");
}

/// 距離区分ごとの解像度密度。予算の判定閾値が未制定であるため、判定の語を付けず実測値だけを出す。
fn 世界メートル毎テクセルを表示する(実行一覧: &[一回の実行]) {
    let Some(実行) = 実行一覧.first() else {
        return;
    };
    let 並び: Vec<String> = 実行
        .世界メートル毎テクセル
        .iter()
        .enumerate()
        .map(|(番号, 長さ)| format!("{番号}={長さ:.6}"))
        .collect();
    println!("  距離区分の世界メートル毎テクセル(閾値未制定のため実測のみ): {}", 並び.join(" "));
}

fn 中央値(実行一覧: &[一回の実行], 読む: impl Fn(&一回の実行) -> f64) -> Option<f64> {
    中央を採る(&実行一覧.iter().map(読む).collect::<Vec<f64>>())
}

fn 中央を採る(一覧: &[f64]) -> Option<f64> {
    let mut 並び = 一覧.to_vec();
    並び.sort_by(f64::total_cmp);
    並び.get(並び.len() / 2).copied()
}
