//! 布のライティングが方向光の強度と環境光係数に追従することの検収入口。
//!
//! 布の描画シェーダーは以前、方向光の色だけを読んで強度(directionalLightColor.w)を掛けず、環境光も0.15の固定値だった。
//! そのため布だけが夜も方向光で照らされ続け、夜の環境光へも追従しなかった。この検収はその欠陥が戻れば落ちる。
//! 見るのは布が覆う画素の平均輝度であり、夜が環境光だけの水準に収まることと、昼がそれより明確に明るいことの2つを課す。
//! 布の領域は同じ時刻の布ありと布なしの差で切り出す。布の色は時刻ごとの光で変わるため、色で切り出すと時刻を跨げない。
//! 描く世界は`cargo xtask cloth-empty`と同じ「群が両方の視錐台の外にある世界」である。この世界の検収計画は自己操作も
//! 画素判定も持たないため、時刻を変えて絵を変えても既存の判定と衝突しない。`--sky`で空を持たない世界の方針を上書きし、
//! 方向光・環境光・露出を時刻から導く経路へ載せる。判定の定数と中身は`judgment`にある。

mod error;
mod judgment;

use std::path::{Path, PathBuf};
use std::process::ExitCode;

use error::布の明るさの時刻追従の検収エラー;

use crate::acceptance::{描画フレーム数, 描画検収の実行環境, 検収の1回の実行, 検収の実行名, 検収シーン名};

const 出力ディレクトリ: &str = "target/cloth_night";
const シェーダーコピー先: &str = "target/cloth_night_shaders";
/// 群がどちらの視錐台にも入らない世界。布だけが画素に出るため、布の領域を切り出しやすい。
const シーン: 検収シーン名 = 検収シーン名::生成する("instance_all_culled");
/// 布が垂れて画素に出る最小の歩進。自己衝突の揺れを溜めないため短く取る。
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(12);
/// 一日内秒。`cargo xtask sky-time`の代表時刻と同じ値を使い、同じ場面を別の観点で語れるようにする。
const 夜の一日内秒: &str = "75600";
const 昼の一日内秒: &str = "43200";

pub fn 布ライティングの追従を確認する() -> ExitCode {
    match 検収する() {
        Ok(要約) => {
            println!("[xtask] cloth-night成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] cloth-night失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

fn 検収する() -> Result<String, 布の明るさの時刻追従の検収エラー> {
    if !crate::gen_source_assets::検証用ソースアセットを生成して成否を返す() || !crate::compile_assets::植生世界を既定で生成する()
    {
        return Err(布の明るさの時刻追従の検収エラー::検証用アセットを生成できなかった);
    }
    let 実行環境 = crate::vegetation_run::植生世界の実行環境を作る(PathBuf::from(出力ディレクトリ))?;
    let 入口 = crate::shader_copy::一時コピーを作る(Path::new(シェーダーコピー先))
        .map_err(布の明るさの時刻追従の検収エラー::シェーダーの一時コピーを作れなかった)?;

    let (夜, 夜png) = 布領域を測る(&実行環境, &入口, "night", 夜の一日内秒)?;
    let (昼, _) = 布領域を測る(&実行環境, &入口, "day", 昼の一日内秒)?;

    let 明るさ = judgment::明るさの時刻への追従を判定する(&夜, &昼)?;
    Ok(format!("{明るさ}、絵は{}", 夜png.display()))
}

/// 1つの時刻の布ありと布なしを描き、布の領域と布ありの絵の置き場を返す。
fn 布領域を測る(
    実行環境: &描画検収の実行環境,
    入口: &Path,
    名前: &str,
    一日内秒: &str,
) -> Result<(judgment::布領域, std::path::PathBuf), 布の明るさの時刻追従の検収エラー> {
    let 布あり = 描く(実行環境, &format!("{名前}_cloth"), 入口, 一日内秒, &["--cloth"])?;
    let 布なし = 描く(実行環境, &format!("{名前}_no_cloth"), 入口, 一日内秒, &[])?;
    let 領域 = judgment::布領域を測る(布あり.画像(), 布なし.画像())?;
    let png = 布あり.書き出し先().目視用の絵へ変換する()?;
    Ok((領域, png))
}

fn 描く(
    実行環境: &描画検収の実行環境,
    名前: &str,
    入口: &Path,
    一日内秒: &str,
    追加: &[&str],
) -> Result<検収の1回の実行, 布の明るさの時刻追従の検収エラー> {
    let mut 引数: Vec<&str> = vec!["--sky", "--time-of-day", 一日内秒];
    引数.extend_from_slice(追加);
    let 実行 = 実行環境.描いて読み戻す(
        検収の実行名::生成する(名前)?,
        &crate::vegetation_run::植生世界の起動指定を組み立てる(シーン, フレーム数, 入口, &引数),
    )?;
    実行.報告().画面へ流す();
    Ok(実行)
}
