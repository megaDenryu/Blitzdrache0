//! この入口が持つ機械判定。受け取るのは撮った件数と食い違った画素の数、返すのは合否である。
//!
//! 判定を段取りから分けるのは、「この入口が何を落とすか」を1箇所で読めるようにするためである。
//! 画素の基準値は1つも持たない。輪郭の階段が減ったかと絵が鈍っていないかの判断は絵を見る人が行う。

use crate::acceptance::{判定の名前, 判定の破れ};

const 撮った時刻の件数: 判定の名前 = 判定の名前::定数から生成する("代表時刻の表から選べた時刻の件数");

pub(super) fn 撮った時刻が台帳の件数と揃うことを確かめる(
    撮った件数: usize, 台帳の件数: usize
) -> Result<(), 判定の破れ> {
    撮った時刻の件数.一致を課す(撮った件数, 台帳の件数)
}

/// 効かせた側と切った側の絵が実際に食い違うことを確かめる。1画素も違わない実行を通すと、
/// 起動指定の取り違えで同じ絵を2枚並べたまま「差が無い」と読む事故が起きる。
pub(super) fn 効かせた絵と切った絵が食い違うことを確かめる(
    時刻名: &str,
    食い違った画素数: usize,
) -> Result<(), 判定の破れ> {
    if 食い違った画素数 == 0 {
        return Err(食い違いの判定名(時刻名).あるはずのものが無い破れ());
    }
    Ok(())
}

fn 食い違いの判定名(時刻名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{時刻名}の効かせた絵と切った絵で食い違う画素"))
}
