//! 時間再構成の目視材料の撮影が返す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。
//! 様式は`acceptance/error.rs`と`texture_compression/error.rs`に倣う。
//!
//! 検収の器の破れと判定の破れを枝で内包するのは、この入口が絵を撮る工程と判定の工程と外部の道具の起動を
//! 一続きに通すためである。3つを別の型で返すと、通す側が段ごとに変換を書くことになる。
//!
//! 判定でも報告の読み取りでもない破れをここが持つのは、目視見本世界の用意と区画を拡大する道具の起動が、
//! どちらもこの入口だけが行う外部への働きかけだからである。人が読む1文へ写すのは`display`が持つ。

mod display;

use std::path::PathBuf;

use crate::acceptance::{判定の破れ, 検収エラー};

#[derive(Debug)]
pub(super) enum 時間再構成の目視材料の撮影エラー {
    検収の器が破れた(検収エラー),
    判定が破れた(判定の破れ),
    目視見本世界を用意できなかった(crate::world_setup::検収世界の用意の破れ),
    /// 切り取る区画の端を、絵の寸法と比べられる数へ直せなかった。
    区画の端を数へ直せなかった {
        端の呼び名: &'static str,
        端の位置: u32,
    },
    /// 撮った絵の一区画を切り取って拡大する外部の道具を起こせなかった。
    区画を拡大する道具を起こせなかった {
        誤り: std::io::Error,
    },
    区画を拡大する道具が失敗して終わった {
        終了状態: String,
    },
    拡大した絵の絶対パスを取れなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
}

impl std::error::Error for 時間再構成の目視材料の撮影エラー {}

impl From<検収エラー> for 時間再構成の目視材料の撮影エラー {
    fn from(破れ: 検収エラー) -> Self {
        Self::検収の器が破れた(破れ)
    }
}

impl From<判定の破れ> for 時間再構成の目視材料の撮影エラー {
    fn from(破れ: 判定の破れ) -> Self {
        Self::判定が破れた(破れ)
    }
}
