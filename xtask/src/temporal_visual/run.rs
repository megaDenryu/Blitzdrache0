//! 目視見本1条件ぶんの起動の指定。受け取るのは時刻と時間再構成の有無、返すのは実行環境へ渡す起動指定である。
//! 起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! `terrain-visual`の起動と別に持つのは、あちらが世界の宣言どおりの1条件だけを撮る入口であり、この入口が時間再構成の
//! 有無を条件として振るためである。あちらの起動指定を条件で振る形にすると、破綻防止帯の判定がどちらの条件の絵を
//! 見ているのかが起動指定で決まってしまう。フレーム数・アセットルート・シーン名はあちらと同じ値を使う。同じ構図の対を
//! 撮ることがこの入口の目的であり、時間再構成の有無以外が1つでも違うと絵の差の由来が読めなくなる。
//!
//! フレーム数120は履歴が積み上がるのに十分である。履歴は無効な状態から始まり1フレーム目は今のフレームをそのまま
//! 出すため、8フレーム(画素内ずらしの列の長さ)を大きく上回る本数が要る。

use std::path::PathBuf;

use crate::acceptance::{アプリの起こし方, アプリの起動指定, 描画フレーム数, 描画検収の実行環境, 検収エラー};
use crate::visual_sample_world::{目視見本世界のアセットルートを作る, 目視見本世界のシーン名};

/// 描くフレーム数。`terrain-visual`と同じ値であり、空と間接照明の焼き上げが定常へ入るまで進める本数である。
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(120);

/// その条件が時間再構成を効かせるか。効かせない側だけが`--no-taa`を受け取る。
#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum 時間再構成の条件 {
    効かせる,
    切る,
}

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        目視見本世界のアセットルートを作る(),
        出力ディレクトリ,
    )
}

pub(super) fn 起動指定を組み立てる(一日内秒: &str, 条件: 時間再構成の条件) -> アプリの起動指定 {
    let 指定 = アプリの起動指定::シーンと枚数を決める(目視見本世界のシーン名, フレーム数).値を持つ選択肢を足す("--time-of-day", 一日内秒);
    match 条件 {
        時間再構成の条件::効かせる => 指定,
        時間再構成の条件::切る => 指定.選択肢を足す("--no-taa"),
    }
}
