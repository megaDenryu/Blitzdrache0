//! 群の世界1つぶんの計数に課す規則。受け取るのは計数報告と期待する個体数、返すのは合否である。
//! 触れるのは計数だけであり、画素にも絵の書き出しにも触れない。
//!
//! 群1つと非空LOD段1つの世界であるため、どのパスも発行数は多くて1回でなければならない。個体数は発行数と別に数える。
//! この世界では全個体がカメラ視錐台にも影の範囲に入るため、シーンパスは全個体を描き、
//! いずれかの距離区分へ影を落とす個体も全個体になる。距離区分ごとの個体数は距離区分の分割で変わるため、個々の距離区分へは期待値を置かない。

use crate::acceptance::{判定の名前, 判定の破れ};
use crate::report_parse::計数報告;

const シーンパスが描いた個体数: 判定の名前 = 判定の名前::定数から生成する("シーンパスが描いた個体数(全個体を描くはずである)");
const 可視判定へ登録された群の候補数: 判定の名前 =
    判定の名前::定数から生成する("可視判定へ登録された群の候補数(この世界は群1つだけである)");
const 影を落とす個体の数: 判定の名前 = 判定の名前::定数から生成する("いずれかの距離区分へ影を落とす個体の数");
const 影の発行を積んだ距離区分: 判定の名前 = 判定の名前::定数から生成する("影の発行を積んだ距離区分");
const 検証層の指摘: 判定の名前 = 判定の名前::定数から生成する("実行で出た検証層の指摘");

pub(super) fn 計数を検査する(計数: &計数報告, 期待個体数: u64) -> Result<(), 判定の破れ> {
    crate::count_consistency::計数の整合を検査する("instance-draw", 計数)?;
    for (パス名, 発行) in crate::report_parse::全パスを並べる(計数) {
        パスの発行数の判定名(&パス名).上限を課す(発行.発行数, 1)?;
    }
    シーンパスが描いた個体数.一致を課す(計数.シーン.個体数, 期待個体数)?;
    // 可視個体の選別の候補数は可視判定へ登録された群の個体だけを数える。この世界は群1つだけであるため期待個体数と一致する。
    可視判定へ登録された群の候補数.一致を課す(計数.可視個体の選別.候補数, 期待個体数)?;
    影を落とす個体の数.一致を課す(計数.可視個体の選別.距離区分の和集合の可視数, 期待個体数)?;
    let 距離区分別の発行数: u64 = 計数.距離区分別のシャドウ.iter().map(|発行| 発行.発行数).sum();
    if 距離区分別の発行数 == 0 {
        return Err(影の発行を積んだ距離区分.あるはずのものが無い破れ());
    }
    検証層の指摘.零件であることを課す(計数.validation件数)
}

fn パスの発行数の判定名(パス名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{パス名}の発行数(群と非空LOD段ごとに1回のはずである)"))
}
