//! 群の世界1つぶんの計数に課す規則。受け取るのは計数報告と期待する個体数、返すのは合否である。
//! 触れるのは計数だけであり、画素にも絵の書き出しにも触れない。
//!
//! 群1つと非空LOD段1つの世界であるため、どのパスも発行数は多くて1回でなければならない。個体数は発行数と別に数える。
//! この世界では全個体がカメラ視錐台にも影の範囲に入るため、シーンパスは全個体を描き、
//! いずれかの距離区分へ影を落とす個体も全個体になる。距離区分ごとの個体数は距離区分の分割で変わるため、個々の距離区分へは期待値を置かない。

use crate::report_parse::計数報告;

pub(super) fn 計数を検査する(計数: &計数報告, 期待個体数: u64) -> Result<(), String> {
    crate::count_consistency::計数の整合を検査する("instance-draw", 計数)?;
    for (パス名, 発行) in crate::report_parse::全パスを並べる(計数) {
        if 発行.発行数 > 1 {
            return Err(format!("群×非空LOD段ごとに1回の発行になっていない: {パス名}が{}回", 発行.発行数));
        }
    }
    if 計数.シーン.個体数 != 期待個体数 {
        return Err(format!("シーンパスが全個体を描いていない: {}体、期待{期待個体数}体", 計数.シーン.個体数));
    }
    // 可視個体の選別の候補数は可視判定へ登録された群の個体だけを数える。この世界は群1つだけであるため期待個体数と一致する。
    if 計数.可視個体の選別.距離区分の和集合の可視数 != 期待個体数 || 計数.可視個体の選別.候補数 != 期待個体数
    {
        return Err(format!(
            "群の候補{}体のうちいずれかの距離区分へ影を落とす個体が{}体である: 期待はどちらも{期待個体数}体",
            計数.可視個体の選別.候補数, 計数.可視個体の選別.距離区分の和集合の可視数
        ));
    }
    let 距離区分別の発行数: u64 = 計数.距離区分別のシャドウ.iter().map(|発行| 発行.発行数).sum();
    if 距離区分別の発行数 == 0 {
        return Err("どの距離区分も影の発行を積んでいない".to_string());
    }
    if 計数.validation件数 != 0 {
        return Err(format!("validationが{}件発生した", 計数.validation件数));
    }
    Ok(())
}
