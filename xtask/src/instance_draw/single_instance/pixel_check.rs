//! 単一個体の読み戻し画像の画素分類。3つの領域で、個体が期待位置に立つこと・その影が床へ伸びること・
//! 個体も影も来ない床が明るいままであることを見る。数え方は`pixel_region`が持ち、ここは領域と明度の境目を決める。
//! 領域は`crates/blitz_asset_compiler/src/vegetation/single_scene.rs`の配置(平行移動62・0・50、Y軸40度、倍率2・3・0.6)、
//! `crates/blitz_app/src/app/scene_camera.rs`の初期カメラ、`crates/blitz_app/src/app/scene_lighting.rs`のライト方針、
//! 1280×720画面を前提に固定している。
//!
//! 個体領域は個体の輪郭を余裕をもって囲む窓であり、その中の明部画素を数える。個体変換が崩れれば個体はこの窓から出て0になる。
//! 対照領域は個体の左側の床であり、明部画素が1つも入らない位置に取る。影領域は個体から-X方向へ伸びる影の内側である。

use crate::acceptance::{判定の名前, 判定の破れ, 読み戻し画像};
use crate::pixel_region::{全画素が範囲内かを確かめる, 明度が範囲内の画素を数える, 画面領域};

/// 個体の輪郭を囲む窓。光を受ける面が明部になる。
const 個体領域: 画面領域 = 画面領域 {
    x開始: 790,
    x終端: 880,
    y開始: 260,
    y終端: 380,
};

/// 個体も影も来ない床。ここが明るいままであることが、判定が空振りでないことを示す。
const 対照領域: 画面領域 = 画面領域 {
    x開始: 150,
    x終端: 650,
    y開始: 180,
    y終端: 330,
};

/// 個体から-X方向へ伸びる影の内側。
const 影領域: 画面領域 = 画面領域 {
    x開始: 580,
    x終端: 760,
    y開始: 358,
    y終端: 372,
};

/// 光を受けた個体の面と、光を受けた床を分ける明度。実測は個体の面が140から156、床が111から123である。
const 明部の下限: u8 = 140;
/// 床が明るいままである明度の範囲。実測は111から123である。
const 床の明度下限: u8 = 100;
const 床の明度上限: u8 = 139;
/// 影の内側の上限。実測は48である。
const 暗部の上限: u8 = 60;
/// 個体が描かれたと認める明部画素の下限。実測は1496画素である。
const 個体の明部画素下限: u64 = 1000;

const 個体が期待位置に描かれた明部の画素: 判定の名前 =
    判定の名前::定数から生成する("個体を囲む窓の明部の画素(個体が期待位置に描かれていれば下限を超える)");
const 個体も影も来ない床の明るい画素: 判定の名前 =
    判定の名前::定数から生成する("個体も影も来ない床で明るいままの画素の数(領域の全画素が明るいはずである)");
const 個体の影が伸びた暗部の画素: 判定の名前 =
    判定の名前::定数から生成する("個体の影が床へ伸びた暗部の画素の数(領域の全画素が暗いはずである)");

pub(super) struct 画素判定結果 {
    pub(super) 個体の明部画素数: u64,
    pub(super) 影の暗部画素数: u64,
}

pub(super) fn 判定する(画像: &読み戻し画像) -> Result<画素判定結果, 判定の破れ> {
    let 個体の明部画素数 = 明度が範囲内の画素を数える(画像, &個体領域, 明部の下限, u8::MAX)?;
    個体が期待位置に描かれた明部の画素.下限を課す(個体の明部画素数, 個体の明部画素下限)?;
    全画素が範囲内かを確かめる(画像, &対照領域, 床の明度下限, 床の明度上限, &個体も影も来ない床の明るい画素)?;
    let 影の暗部画素数 = 全画素が範囲内かを確かめる(画像, &影領域, 0, 暗部の上限, &個体の影が伸びた暗部の画素)?;
    Ok(画素判定結果 {
        個体の明部画素数,
        影の暗部画素数,
    })
}
