//! 読み戻し画像の画素判定。4個体が互いに離れた領域へ描かれ、個体の位置で番兵背景色が消えていることを確かめる。
//! 画面を4分割した各領域に非背景の塊があること、および中央で交わる帯が全て背景であることの2つで「離れている」を判定する。
//! 塊の位置は`crates/blitz_app/src/app/scene_camera.rs`の植生シーンの初期カメラと1280×720画面を前提に固定している。

use super::run::実行結果;

/// クリアカラーをsRGBへ写した番兵背景色。個体が描かれた画素はこの色でなくなる。
const 背景RGB: [u8; 3] = [63, 75, 97];

/// 中央で交わる帯の半幅。個体の最寄りの縁までは40画素以上あるため、この幅なら個体が掛からない。
const 分離帯半幅: usize = 20;

/// 1つの領域が個体を描いたと認める非背景画素の下限。4個体の実測はいずれも900画素を超える。
const 領域の非背景画素下限: u64 = 300;

pub(super) struct 画素判定結果 {
    pub(super) 領域別非背景画素数: [u64; 4],
}

pub(super) fn 判定する(画像: &実行結果) -> Result<画素判定結果, String> {
    let 半幅 = 画像.幅 / 2;
    let 半高 = 画像.高さ / 2;
    let 領域別非背景画素数 = [
        非背景を数える(画像, 0, 半幅, 0, 半高),
        非背景を数える(画像, 半幅, 画像.幅, 0, 半高),
        非背景を数える(画像, 0, 半幅, 半高, 画像.高さ),
        非背景を数える(画像, 半幅, 画像.幅, 半高, 画像.高さ),
    ];
    for (領域番号, 画素数) in 領域別非背景画素数.iter().enumerate() {
        if *画素数 < 領域の非背景画素下限 {
            return Err(format!("領域{領域番号}の非背景画素が{画素数}で下限{領域の非背景画素下限}に届かない"));
        }
    }
    let 縦帯 = 非背景を数える(画像, 半幅 - 分離帯半幅, 半幅 + 分離帯半幅, 0, 画像.高さ);
    let 横帯 = 非背景を数える(画像, 0, 画像.幅, 半高 - 分離帯半幅, 半高 + 分離帯半幅);
    if 縦帯 != 0 || 横帯 != 0 {
        return Err(format!("中央の分離帯に非背景画素が残った: 縦{縦帯}画素、横{横帯}画素"));
    }
    Ok(画素判定結果 { 領域別非背景画素数 })
}

fn 非背景を数える(画像: &実行結果, x開始: usize, x終端: usize, y開始: usize, y終端: usize) -> u64 {
    let mut 件数 = 0;
    for y in y開始..y終端 {
        for x in x開始..x終端 {
            let 位置 = (y * 画像.幅 + x) * 4;
            if 画像.rgba8[位置..位置 + 3] != 背景RGB {
                件数 += 1;
            }
        }
    }
    件数
}
