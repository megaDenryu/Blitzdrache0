//! 個体が1体だけのインスタンス群を実機で検収する工程。受け取るのは出力先とシェーダー入口、返すのは実測値の要約である。
//!
//! 個体が1体の対象は専用のストレージバッファを確保せず、描画対象シェーダー定数の先頭112バイトを個体変換1件として読む。
//! この配置を崩す変更(シェーダー定数の先頭から変換を動かす等)は、恒等でないTRSを与えた1体の絵にしか現れないため、
//! 4個体・64個体の条件では捕まらない。平行移動・回転・非一様スケールをすべて含む1体をシーンパスとシャドウパスの
//! 両方の画素で見ることが、この条件の目的である。
//! 画素の分類は`pixel_check`にある。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「描画発行」

mod pixel_check;

use std::path::Path;

use crate::acceptance::{描画フレーム数, 描画検収の実行環境, 検収の実行名, 検収シーン名};
use crate::report_parse::計数報告;
use crate::vegetation_run;

const シーンの綴り: &str = "vegetation_single";
const シーン: 検収シーン名 = 検収シーン名::生成する(シーンの綴り);
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(12);

/// 影を見るため`--unlit`を付けない。可視判定は既定の有効のまま通し、単一個体が可視判定の経路も踏むことを同時に見る。
const 起動引数: [&str; 3] = ["--no-post", "--report-draw-issue", "--report-memory"];

/// 群1つと床1つの2対象であり、どちらも個体1体である。
const 期待発行数: u64 = 2;
const 期待個体数: u64 = 2;

pub(super) fn 検収する(実行環境: &描画検収の実行環境, シェーダー入口: &Path) -> Result<String, String> {
    let 実行 = 実行環境.描いて読み戻す(
        検収の実行名::生成する(シーンの綴り)?,
        &vegetation_run::植生世界の起動指定を組み立てる(シーン, フレーム数, シェーダー入口, &起動引数),
    )?;
    実行.報告().画面へ流す();
    let 画素 = pixel_check::判定する(実行.画像())?;
    計数を検査する(&crate::report_parse::取り出す(実行.報告())?)?;
    Ok(format!("個体の明部{}画素・影の暗部{}画素", 画素.個体の明部画素数, 画素.影の暗部画素数))
}

/// 群と床がそれぞれ1回ずつ発行し、シーンパスは個体を1体ずつ描く。単一個体は可視判定の対象になるため、
/// シーンパスの可視数が候補数と等しいことも見る。ここが減れば1体の可視判定が誤って落としている。
/// 影の側は距離区分ごとに分かれるため、個々の距離区分へ期待値を置かずに「いずれかの距離区分へ群の全個体が影を落とすこと」で見る。
/// 距離区分ごとの発行数は多くて期待発行数である。
fn 計数を検査する(計数: &計数報告) -> Result<(), String> {
    crate::count_consistency::計数の整合を検査する("単一個体", 計数)?;
    if 計数.シーン.発行数 != 期待発行数 || 計数.シーン.個体数 != 期待個体数 {
        return Err(format!(
            "シーンパスの発行数{}・個体数{}が期待の{期待発行数}・{期待個体数}と違う",
            計数.シーン.発行数, 計数.シーン.個体数
        ));
    }
    if 計数.シーン.可視数 != 計数.シーン.候補数 {
        return Err(format!(
            "シーンパスの可視数{}が候補数{}と違う: 1体の対象が可視判定で落ちている",
            計数.シーン.可視数, 計数.シーン.候補数
        ));
    }
    for (番号, 距離区分) in 計数.距離区分別のシャドウ.iter().enumerate() {
        if 距離区分.発行数 > 期待発行数 {
            return Err(format!("シャドウ距離区分{番号}の発行数{}が期待の{期待発行数}を超えた", 距離区分.発行数));
        }
    }
    // 可視個体の選別の候補数は可視判定へ登録された群の個体だけを数える。床は通常メッシュであり登録されないため、
    // ここでの候補数は群の1体であって描画発行の候補数(群と床の2体)とは違う。
    let 可視個体の選別 = &計数.可視個体の選別;
    if 可視個体の選別.距離区分の和集合の可視数 != 可視個体の選別.候補数 || 可視個体の選別.候補数 == 0 {
        return Err(format!(
            "いずれかの距離区分へ影を落とす個体が{}体で群の候補{}体と違う",
            可視個体の選別.距離区分の和集合の可視数, 可視個体の選別.候補数
        ));
    }
    if 計数.validation件数 != 0 {
        return Err(format!("validationが{}件発生した", 計数.validation件数));
    }
    Ok(())
}
