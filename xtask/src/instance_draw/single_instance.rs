//! 個体が1体だけのインスタンス群を実機で検収する工程。受け取るのは出力先とシェーダー入口、返すのは実測値の要約である。
//!
//! 個体が1体の対象は専用のストレージバッファを確保せず、描画対象ユニフォームの先頭112バイトを個体変換1件として読む。
//! この配置を崩す変更(ユニフォームの先頭から変換を動かす等)は、恒等でないTRSを与えた1体の絵にしか現れないため、
//! 4個体・64個体の条件では捕まらない。平行移動・回転・非一様スケールをすべて含む1体をシーンパスとシャドウパスの
//! 両方の画素で見ることが、この条件の目的である。
//! 画素の分類は`pixel_check`にある。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「描画発行」

mod pixel_check;

use std::path::Path;

use crate::report_parse::計数報告;
use crate::vegetation_run;

const シーン: &str = "vegetation_single";
const フレーム数: &str = "12";

/// 影を見るため`--unlit`を付けない。可視判定は既定の有効のまま通し、単一個体が可視判定の経路も踏むことを同時に見る。
const 起動引数: [&str; 3] = ["--no-post", "--report-draw-issue", "--report-memory"];

/// 群1つと床1つの2対象であり、どちらも個体1体である。
const 期待発行数: u64 = 2;
const 期待個体数: u64 = 2;

pub(super) fn 検収する(出力先: &Path, シェーダー入口: &Path) -> Result<String, String> {
    let 実行 = vegetation_run::描画する(&出力先.join(シーン), シーン, シェーダー入口, フレーム数, &起動引数)?;
    let 画素 = pixel_check::判定する(&実行)?;
    計数を検査する(&crate::report_parse::取り出す(&実行.標準出力)?)?;
    Ok(format!("個体の明部{}画素・影の暗部{}画素", 画素.個体の明部画素数, 画素.影の暗部画素数))
}

/// 群と床がそれぞれ1回ずつ発行し、シーンパスは個体を1体ずつ描く。単一個体は可視判定の対象になるため、
/// シーンパスの可視数が候補数と等しいことも見る。ここが減れば1体の可視判定が誤って落としている。
/// 影の側は帯ごとに分かれるため、個々の帯へ期待値を置かずに「いずれかの帯へ群の全個体が影を落とすこと」で見る。
/// 帯ごとの発行数は多くて期待発行数である。
fn 計数を検査する(計数: &計数報告) -> Result<(), String> {
    crate::count_consistency::計数の整合を検査する("単一個体", 計数)?;
    if 計数.シーン.発行数 != 期待発行数 || 計数.シーン.個体数 != 期待個体数 {
        return Err(format!(
            "シーンパスの発行数{}・個体数{}が期待の{期待発行数}・{期待個体数}と違う",
            計数.シーン.発行数, 計数.シーン.個体数
        ));
    }
    if 計数.シーン.可視数 != 計数.シーン.候補数 {
        return Err(format!(
            "シーンパスの可視数{}が候補数{}と違う: 1体の対象が可視判定で落ちている",
            計数.シーン.可視数, 計数.シーン.候補数
        ));
    }
    for (番号, 帯) in 計数.帯別シャドウ.iter().enumerate() {
        if 帯.発行数 > 期待発行数 {
            return Err(format!("シャドウ帯{番号}の発行数{}が期待の{期待発行数}を超えた", 帯.発行数));
        }
    }
    // 群選択の候補数は可視判定へ登録された群の個体だけを数える。床は通常メッシュであり登録されないため、
    // ここでの候補数は群の1体であって描画発行の候補数(群と床の2体)とは違う。
    let 群選択 = &計数.群選択;
    if 群選択.帯和集合可視数 != 群選択.候補数 || 群選択.候補数 == 0 {
        return Err(format!(
            "いずれかの帯へ影を落とす個体が{}体で群の候補{}体と違う",
            群選択.帯和集合可視数, 群選択.候補数
        ));
    }
    if 計数.validation件数 != 0 {
        return Err(format!("validationが{}件発生した", 計数.validation件数));
    }
    Ok(())
}
