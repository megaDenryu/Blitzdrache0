//! 計器から見た材質の本数の判定。受け取るのは1回の実行の計数報告、返すのは合否である。
//!
//! 画素の判定と分けるのは、入力も根拠も別だからである。画素は「作者が与えた色が絵に出たか」を見るのに対し、
//! ここは「材質スロットの数だけ描画発行が立ったか」という描画側の数を見る。
//! glbは材質スロットごとにプリミティブを分け、レンダラーはプリミティブごとに1回発行するため、
//! 材質が縮退すれば発行数が減る。画素が偶然通っても、この数がプリミティブの脱落を捕まえる。

use crate::report_parse::計数報告;

pub(super) fn 検査する(計数: &計数報告, 材質の数: usize) -> Result<(), String> {
    crate::count_consistency::計数の整合を検査する("prop-multi-material-draw", 計数)?;
    let 期待発行数 = u64::try_from(材質の数).map_err(|誤り| format!("材質の数を発行数へ写せない: {誤り}"))?;
    if 計数.シーン.発行数 != 期待発行数 {
        return Err(format!(
            "シーンパスの発行数が{}である。材質{材質の数}個ぶんのプリミティブが立つなら{期待発行数}になる",
            計数.シーン.発行数
        ));
    }
    if 計数.validation件数 != 0 {
        return Err(format!("validationが{}件発生した", 計数.validation件数));
    }
    Ok(())
}
