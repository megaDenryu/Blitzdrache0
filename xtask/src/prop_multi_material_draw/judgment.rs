//! 材質の境界が実アセットの絵に出ていることの判定。受け取るのは色の分布、返すのは合格の要約である。
//! 計器から見た判定は`count_judgment`が持つ。
//!
//! 判定の骨は「上位の色が材質の数だけ立ち、そのどれもが小さすぎず、互いに別の色であり、合わせて物体をほぼ覆う」である。
//! 材質の縮退はこの形で必ず落ちる。全プリミティブが1つの材質へ縮退すれば色の山は1本になり、
//! 2位と3位には輪郭のにじみしか残らないため、下限の割合を満たせない。
//! 色を絶対値で照合しないのは、アセットが宣言したベースカラーの写しを検収側へ持たないためである。
//! 写しを持つと、アセットの色を変えたときにこの検収だけが無言で通らなくなる。

use super::material_pixels::色の分布;

/// 物体が占める画素の割合の下限。これを下回るなら小物が描かれていないか、構図から外れている。
const 物体の占有率の下限: f64 = 0.02;
/// 材質1つが物体画素のうち占める割合の下限。最も小さい材質でも、輪郭のにじみとは桁が違う面積を持つ。
const 材質1つの占有率の下限: f64 = 0.06;
/// 上位の色が物体画素を覆う割合の下限。残りは面と面の境界にできるにじみである。
const 覆う割合の下限: f64 = 0.80;
/// 2つの色を別の材質と言うための、対応する成分の差の下限。読み戻しの符号化の揺れ(数階調)とは桁が違う値である。
const 成分差の下限: u8 = 30;

pub(super) fn 材質の境界を検査する(分布: &色の分布) -> Result<String, String> {
    let 上位 = &分布.多い順の色;
    if 上位.len() < super::材質の数 {
        return Err(format!(
            "背景でない画素に{}種類の色しか無い。材質{}個ぶんの色が立っていない",
            上位.len(),
            super::材質の数
        ));
    }
    let 上位 = &上位[..super::材質の数];
    占有率を検査する(分布)?;
    割合を検査する(分布.物体画素数, 上位)?;
    互いに別の色であることを検査する(上位)?;
    Ok(format!(
        "背景色{:?}、物体画素{}、上位{}色は{:?}",
        分布.背景色,
        分布.物体画素数,
        super::材質の数,
        上位
    ))
}

fn 占有率を検査する(分布: &色の分布) -> Result<(), String> {
    if 分布.物体画素数 == 0 {
        return Err(format!("背景色{:?}でない画素が1つも無い。物体が描かれていない", 分布.背景色));
    }
    let 占有率 = 割合を求める(分布.物体画素数, 分布.全画素数)?;
    if 占有率 < 物体の占有率の下限 {
        return Err(format!(
            "物体が占める割合{占有率:.4}が下限{物体の占有率の下限}に届かない。小物が構図から外れているか極端に小さく写っている"
        ));
    }
    Ok(())
}

fn 割合を検査する(物体画素数: u64, 上位: &[([u8; 3], u64)]) -> Result<(), String> {
    let mut 合計 = 0u64;
    for (色, 件数) in 上位 {
        let 割合 = 割合を求める(*件数, 物体画素数)?;
        if 割合 < 材質1つの占有率の下限 {
            return Err(format!(
                "色{色:?}が物体画素の{割合:.4}しか占めず、材質1つの下限{材質1つの占有率の下限}に届かない。材質が縮退している"
            ));
        }
        合計 += 件数;
    }
    let 覆う割合 = 割合を求める(合計, 物体画素数)?;
    if 覆う割合 < 覆う割合の下限 {
        return Err(format!(
            "上位の色が物体画素の{覆う割合:.4}しか覆わず、下限{覆う割合の下限}に届かない。塗りが材質ごとに一様でない"
        ));
    }
    Ok(())
}

fn 互いに別の色であることを検査する(上位: &[([u8; 3], u64)]) -> Result<(), String> {
    for (添字, (色, _)) in 上位.iter().enumerate() {
        for (相手, _) in &上位[添字 + 1..] {
            let 最大の差 = (0..3).map(|成分| 色[成分].abs_diff(相手[成分])).max().unwrap_or(0);
            if 最大の差 < 成分差の下限 {
                return Err(format!(
                    "色{色:?}と色{相手:?}の成分の差が最大{最大の差}で、別の材質と言える下限{成分差の下限}に届かない"
                ));
            }
        }
    }
    Ok(())
}

fn 割合を求める(分子: u64, 分母: u64) -> Result<f64, String> {
    let 分母 = u32::try_from(分母).map_err(|誤り| format!("画素数を割合の分母へ写せない: {誤り}"))?;
    if 分母 == 0 {
        return Err("背景でない画素が1つも無い".to_string());
    }
    let 分子 = u32::try_from(分子).map_err(|誤り| format!("画素数を割合の分子へ写せない: {誤り}"))?;
    Ok(f64::from(分子) / f64::from(分母))
}
