//! 小物の材質境界の検収エラーを人が読む1文へ写すトレイト実装。枝ごとに、どの前提がどう破れたかを出す。
//! 実装を型の定義と分けるのは、外部トレイトの実装が型自身の持ち物とは別の軸であるためである。

use std::fmt;

use super::小物の材質境界の検収エラー;

impl fmt::Display for 小物の材質境界の検収エラー {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::検収の器が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::判定が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::検証用アセットを生成できなかった => write!(書き手, "検証用アセットの生成に失敗した"),
            Self::実行時形式が作られていない { パス } => write!(
                書き手,
                "{パス}が作られていない。外部のアセットリポジトリが見つからず宣言が飛ばされた可能性が高い(compile-assetsの出力に飛ばした理由が出る)"
            ),
        }
    }
}
