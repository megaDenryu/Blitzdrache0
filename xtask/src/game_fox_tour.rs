//! クソゲー1本目「キツネの場所巡り」の通しの検収の入口。担当するのは、乱数の種からマップを作る決定性を確かめることと、
//! 決定的な台本でタイトルから終了までを1周させることと、その途中の絵を目視の材料として書き出すことである。
//!
//! 生成の検収(クリーンな2つの生成のバイト一致と、同じ種での再実行が1本も焼き直さないこと)は`map_generation_check`が持つ。
//! 撮る条件の台帳は`shot_plan`が持つ。タイトル・プレイ中・目的地付近・終了確認の4枚を目視の材料として書き出し、
//! 終了まで進む条件は途中でイベントループを閉じるため絵を残さない。そちらが確かめるのは終了の決定へ至ることである。
//! 絵の合否は親エージェントの目視が決める。ここが担うのは、決定性と進行の値を機械で確かめることである。

pub(crate) mod error;
mod judgment;
pub(crate) mod map_generation_check;
mod run;
mod shot_plan;

use std::path::PathBuf;
use std::process::ExitCode;

use error::場所巡りの通しの検収エラー;

use crate::acceptance::{描画検収の実行環境, 検収の実行名, 検収エラー};

use shot_plan::{
    タイトルの撮影, プレイ中の撮影, 台本なしの実行, 撮影の条件, 目的地付近の二度目の撮影, 目的地付近の撮影, 終了までの実行, 終了確認の撮影,
};

const 出力ディレクトリ: &str = "target/game_fox_tour";

pub fn 実行する() -> ExitCode {
    match 検収する() {
        Ok(要約) => {
            println!("[xtask] game-fox-tour成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] game-fox-tour失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

fn 検収する() -> Result<String, 場所巡りの通しの検収エラー> {
    let マップの要約 = map_generation_check::種からの生成を確かめる(crate::fox_tour_map_seed::決定性検収の乱数の種)?;
    let 実行環境 = crate::fox_tour_launch::場所巡りの世界の検収の実行環境を作る(
        PathBuf::from(出力ディレクトリ),
        map_generation_check::撮影用の実行時アセットルート(),
    )?;

    let タイトル = 台本の操作でその条件の絵を撮る(&実行環境, &タイトルの撮影)?;
    let プレイ中 = 台本の操作でその条件の絵を撮る(&実行環境, &プレイ中の撮影)?;
    let 目的地付近 = 台本の操作でその条件の絵を撮る(&実行環境, &目的地付近の撮影)?;
    let 目的地付近の二度目 = 台本の操作でその条件の絵を撮る(&実行環境, &目的地付近の二度目の撮影)?;
    let 終了確認 = 台本の操作でその条件の絵を撮る(&実行環境, &終了確認の撮影)?;
    let 終了まで = 台本の操作でその条件の絵を撮る(&実行環境, &終了までの実行)?;
    let 台本なし = run::描画する(
        &実行環境,
        台本なしの実行.出力名,
        台本なしの実行.フレーム数,
        run::操作の出どころ::実行時の入力,
    )?;

    judgment::台本が目的地へ着くことを確かめる(&目的地付近)?;
    judgment::台本が目的地へ着くことを確かめる(&終了確認)?;
    judgment::台本が終了まで進むことを確かめる(&終了まで)?;
    let 決定性 = judgment::二回の実行が同じ進行で終わることを確かめる(&目的地付近, &目的地付近の二度目)?;
    judgment::二回の実行の絵がバイト一致することを確かめる(
        &実行環境,
        目的地付近の撮影.出力名,
        目的地付近の二度目の撮影.出力名,
    )?;
    judgment::台本なしの実行がタイトルのまま終わることを確かめる(&台本なし, &目的地付近)?;

    let 目視材料 = 目視材料のパスを並べる(&実行環境, &[&タイトルの撮影, &プレイ中の撮影, &目的地付近の撮影, &終了確認の撮影])?;
    let タイトルの段階 = タイトル.最後の進行段階;
    let プレイ中の段階 = プレイ中.最後の進行段階;
    Ok(format!(
        "{マップの要約}、{決定性}、タイトルの段階は{タイトルの段階}、プレイ中の段階は{プレイ中の段階}、目視材料は{目視材料}"
    ))
}

fn 台本の操作でその条件の絵を撮る(
    実行環境: &描画検収の実行環境, 条件: &撮影の条件
) -> Result<run::実行の進行, 検収エラー> {
    run::描画する(実行環境, 条件.出力名, 条件.フレーム数, run::操作の出どころ::決定的な台本)
}

fn 目視材料のパスを並べる(
    実行環境: &描画検収の実行環境, 条件一覧: &[&撮影の条件]
) -> Result<String, 検収エラー> {
    let mut パス一覧 = Vec::with_capacity(条件一覧.len());
    for 条件 in 条件一覧 {
        let 実行名 = 検収の実行名::生成する(条件.出力名)?;
        パス一覧.push(実行環境.同じ置き場の書き出しを目視用の絵へ変換する(実行名)?.display().to_string());
    }
    Ok(パス一覧.join("、"))
}
