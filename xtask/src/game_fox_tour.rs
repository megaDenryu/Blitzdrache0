//! クソゲー1本目「キツネの場所巡り」の通しの検収の入口。担当するのは、乱数の種からマップを作る決定性を確かめることと、
//! 決定的な台本でタイトルから終了までを1周させることと、その途中の絵を目視の材料として書き出すことである。
//!
//! 生成の検収(クリーンな2つの生成のバイト一致と、同じ種での再実行が1本も焼き直さないこと)は`map_generation_check`が持つ。
//! 撮る条件の台帳は`shot_plan`が持つ。タイトル・プレイ中・目的地付近・終了確認の4枚を目視の材料として書き出し、
//! 終了まで進む条件は途中でイベントループを閉じるため絵を残さない。そちらが確かめるのは終了の決定へ至ることである。
//! 絵の合否は親エージェントの目視が決める。ここが担うのは、決定性と進行の値を機械で確かめることである。

mod judgment;
mod map_generation_check;
mod run;
mod shot_plan;

use std::path::{Path, PathBuf};
use std::process::ExitCode;

use shot_plan::{
    タイトルの撮影, プレイ中の撮影, 台本なしの実行, 撮影の条件, 目的地付近の二度目の撮影, 目的地付近の撮影, 終了までの実行, 終了確認の撮影,
};

const 出力ディレクトリ: &str = "target/game_fox_tour";

/// 検収が使う乱数の種。リポジトリへ収めたassets/fox_tour_world/はこの種から作ったものであり、
/// 別の種を使うと生成物が入れ替わって差分が出る。
const 検収の種: &str = "20260810";

pub fn 実行する() -> ExitCode {
    match 検収する() {
        Ok(要約) => {
            println!("[xtask] game-fox-tour成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] game-fox-tour失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

fn 検収する() -> Result<String, String> {
    let マップの要約 = map_generation_check::種からの生成を確かめる(検収の種)?;
    let 出力先 = PathBuf::from(出力ディレクトリ);
    std::fs::create_dir_all(&出力先).map_err(|誤り| format!("出力先を作れなかった: {誤り}"))?;

    let タイトル = 台本の操作でその条件の絵を撮る(&出力先, &タイトルの撮影)?;
    let プレイ中 = 台本の操作でその条件の絵を撮る(&出力先, &プレイ中の撮影)?;
    let 目的地付近 = 台本の操作でその条件の絵を撮る(&出力先, &目的地付近の撮影)?;
    let 目的地付近の二度目 = 台本の操作でその条件の絵を撮る(&出力先, &目的地付近の二度目の撮影)?;
    let 終了確認 = 台本の操作でその条件の絵を撮る(&出力先, &終了確認の撮影)?;
    let 終了まで = 台本の操作でその条件の絵を撮る(&出力先, &終了までの実行)?;
    let 台本なし = run::描画する(
        &出力先,
        台本なしの実行.出力名,
        台本なしの実行.フレーム数,
        run::操作の出どころ::実行時の入力,
    )?;

    judgment::台本が目的地へ着くことを確かめる(&目的地付近)?;
    judgment::台本が目的地へ着くことを確かめる(&終了確認)?;
    judgment::台本が終了まで進むことを確かめる(&終了まで)?;
    let 決定性 = judgment::二回の実行が同じ進行で終わることを確かめる(&目的地付近, &目的地付近の二度目)?;
    judgment::二回の実行の絵がバイト一致することを確かめる(&出力先, 目的地付近の撮影.出力名, 目的地付近の二度目の撮影.出力名)?;
    judgment::台本なしの実行がタイトルのまま終わることを確かめる(&台本なし, &目的地付近)?;

    let 目視材料 = 目視材料のパスを並べる(&出力先, &[&タイトルの撮影, &プレイ中の撮影, &目的地付近の撮影, &終了確認の撮影])?;
    let タイトルの段階 = タイトル.最後の進行段階;
    let プレイ中の段階 = プレイ中.最後の進行段階;
    Ok(format!(
        "{マップの要約}、{決定性}、タイトルの段階は{タイトルの段階}、プレイ中の段階は{プレイ中の段階}、目視材料は{目視材料}"
    ))
}

fn 台本の操作でその条件の絵を撮る(出力先: &Path, 条件: &撮影の条件) -> Result<run::実行の進行, String> {
    run::描画する(出力先, 条件.出力名, 条件.フレーム数, run::操作の出どころ::決定的な台本)
}

fn 目視材料のパスを並べる(出力先: &Path, 条件一覧: &[&撮影の条件]) -> Result<String, String> {
    let mut パス一覧 = Vec::with_capacity(条件一覧.len());
    for 条件 in 条件一覧 {
        let png = crate::raw_png::変換する(&出力先.join(条件.出力名))?;
        パス一覧.push(png.display().to_string());
    }
    Ok(パス一覧.join("、"))
}
