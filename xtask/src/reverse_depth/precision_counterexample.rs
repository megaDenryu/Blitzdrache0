//! 既知距離の合成幾何を両方の投影へ通し、解析距離に対する遠方精度を反証する。

use super::depth_image::{標準深度の奥行き, 近クリップ, 逆向き深度の奥行き, 遠クリップ};
use super::error::逆Z検収エラー;

/// 標準Zの精度低下が現れる200m、遠クリップの中央と直前を同時に覆う。
const 合成幾何の距離一覧: [f32; 3] = [200.0, 1000.0, 1900.0];
/// 1mmは近距離の実寸下限、相対1e-5は単精度の投影と復元を往復する演算への余白である。
const 絶対許容メートル: f64 = 0.001;
const 相対許容: f64 = 1.0e-5;

pub(super) fn 奥行き精度を反証する() -> Result<String, 逆Z検収エラー> {
    let mut 標準の最大誤差: f64 = 0.0;
    let mut 逆向きの最大誤差: f64 = 0.0;
    for 距離 in 合成幾何の距離一覧 {
        let 解析距離 = f64::from(距離);
        let 標準誤差 = (標準深度の奥行き(標準投影の深度(距離)) - 解析距離).abs();
        let 逆向き誤差 = (逆向き深度の奥行き(逆向き投影の深度(距離)) - 解析距離).abs();
        let 許容 = 絶対許容メートル.max(解析距離 * 相対許容);
        if 逆向き誤差 > 許容 || 逆向き誤差 >= 標準誤差 {
            return Err(逆Z検収エラー::判定が不合格(format!(
                "合成幾何{距離}mの精度反証が不成立(標準Z誤差{標準誤差:.9}m、逆向き深度誤差{逆向き誤差:.9}m、許容{許容:.9}m)"
            )));
        }
        標準の最大誤差 = 標準の最大誤差.max(標準誤差);
        逆向きの最大誤差 = 逆向きの最大誤差.max(逆向き誤差);
    }
    Ok(format!(
        "合成幾何の解析値との最大差は標準Z{標準の最大誤差:.9}m・逆向き深度{逆向きの最大誤差:.9}m"
    ))
}

fn 標準投影の深度(距離: f32) -> f32 {
    let 近 = 近クリップ;
    let 遠 = 遠クリップ;
    let 係数 = 遠 / (近 - 遠);
    let 定数 = 近 * 遠 / (近 - 遠);
    (係数 * -距離 + 定数) / 距離
}

fn 逆向き投影の深度(距離: f32) -> f32 {
    let 近 = 近クリップ;
    let 遠 = 遠クリップ;
    let 係数 = 近 / (遠 - 近);
    let 定数 = 遠 * 近 / (遠 - 近);
    (係数 * -距離 + 定数) / 距離
}

