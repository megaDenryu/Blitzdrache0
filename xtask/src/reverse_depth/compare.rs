//! 対照と候補を背景の意味と提示色で比べ、raw深度の相補関係を診断として数える。

mod color;
mod provenance;

use super::depth_image::深度画像;
use super::error::逆Z検収エラー;
use crate::acceptance::{描画検収の実行環境, 書き出しの形式, 検収の実行名};

pub(super) fn 対照と候補を比べる(環境: &描画検収の実行環境) -> Result<String, 逆Z検収エラー> {
    provenance::対照の深度契約を検査する()?;
    let 対照色 = 環境.同じ置き場の書き出しを読み戻す(実行名を作る("reference_color")?)?;
    let 候補色 = 環境.同じ置き場の書き出しを読み戻す(実行名を作る("candidate_color")?)?;
    if !対照色.寸法が同じか(&候補色) {
        return Err(逆Z検収エラー::判定が不合格("提示色の寸法が違う".to_string()));
    }
    let 対照深度のバイト列 = 深度を読み再撮影との一致を確かめる(環境, "reference_depth")?;
    let 候補深度のバイト列 = 深度を読み再撮影との一致を確かめる(環境, "candidate_depth")?;
    let 対照深度 = 深度画像::バイト列から読む(&対照深度のバイト列, 対照色.画素数())?;
    let 候補深度 = 深度画像::バイト列から読む(&候補深度のバイト列, 対照色.画素数())?;
    let (幾何画素数, 相補の最大表現間隔数) = 深度を比べる(&対照深度, &候補深度)?;
    let 色差 = color::色を比べる(&対照色, &候補色, &候補深度)?;
    Ok(format!(
        "mask完全一致・深度の非数/無限大0({幾何画素数}幾何画素)・深度の再撮影一致・輪郭外の検査{}画素(うち幾何{}画素)・輪郭から2px超離れた重大色差0、raw深度相補の最大差は単精度の隣接表現{相補の最大表現間隔数}段(診断値)、提示色最大差{}階調・差画素{}/{}(診断値)",
        色差.輪郭外の検査画素数,
        色差.輪郭外の幾何画素数,
        色差.最大差,
        色差.差画素数,
        対照色.画素数()
    ))
}

fn 深度を読み再撮影との一致を確かめる(環境: &描画検収の実行環境, 名: &str) -> Result<Vec<u8>, 逆Z検収エラー> {
    let 深度 = 環境.同じ置き場の書き出しのバイト列を読む(実行名を作る(名)?, 書き出しの形式::最終深度)?;
    let 再撮影名 = format!("{名}_repeat");
    let 再撮影 = 環境.同じ置き場の書き出しのバイト列を読む(実行名を作る(&再撮影名)?, 書き出しの形式::最終深度)?;
    if 深度 != 再撮影 {
        return Err(逆Z検収エラー::判定が不合格(
            format!("{名}と同じ条件の再撮影深度がバイト一致しない"),
        ));
    }
    Ok(深度)
}

fn 実行名を作る(名: &str) -> Result<検収の実行名, 逆Z検収エラー> {
    Ok(検収の実行名::生成する(名)?)
}

fn 深度を比べる(対照: &深度画像, 候補: &深度画像) -> Result<(usize, u32), 逆Z検収エラー> {
    let mut 幾何画素数 = 0;
    let mut 相補の最大表現間隔数 = 0;
    for (対照値, 候補値) in 対照.深度列().iter().zip(候補.深度列()) {
        if !対照値.is_finite() || !候補値.is_finite() {
            return Err(逆Z検収エラー::判定が不合格("深度にNaNまたは無限大がある".to_string()));
        }
        let 対照幾何 = *対照値 < 1.0;
        let 候補幾何 = *候補値 > 0.0;
        if 対照幾何 != 候補幾何 {
            return Err(逆Z検収エラー::判定が不合格("背景とジオメトリのmaskが一致しない".to_string()));
        }
        if 対照幾何 {
            幾何画素数 += 1;
            let 対照の相補 = 1.0 - *対照値;
            相補の最大表現間隔数 = 相補の最大表現間隔数.max(対照の相補.to_bits().abs_diff(候補値.to_bits()));
        }
    }
    Ok((幾何画素数, 相補の最大表現間隔数))
}
