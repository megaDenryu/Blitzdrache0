//! 対照と候補を背景の意味と提示色で比べ、raw深度の相補関係を診断として数える。

use std::path::Path;

use super::depth_image::深度画像;
use super::error::逆Z検収エラー;
use crate::acceptance::{描画検収の実行環境, 書き出しの形式, 検収の実行名};

const 色差画素の割合の分母: usize = 10_000;

pub(super) fn 対照と候補を比べる(環境: &描画検収の実行環境) -> Result<String, 逆Z検収エラー> {
    let 由来 = Path::new("target/reverse_depth").join(super::対照の由来ファイル名);
    if !由来.exists() {
        return Err(逆Z検収エラー::対照の由来が無い(由来));
    }
    let 対照色 = 環境.同じ置き場の書き出しを読み戻す(名前("reference_color")?)?;
    let 候補色 = 環境.同じ置き場の書き出しを読み戻す(名前("candidate_color")?)?;
    if !対照色.寸法が同じか(&候補色) {
        return Err(逆Z検収エラー::判定が不合格("提示色の寸法が違う".to_string()));
    }
    let 対照深度 = 深度画像::バイト列から読む(&深度を読む(環境, "reference_depth")?, 対照色.画素数())?;
    let 候補深度 = 深度画像::バイト列から読む(&深度を読む(環境, "candidate_depth")?, 対照色.画素数())?;
    let (幾何画素数, 相補の最大表現間隔数) = 深度を比べる(&対照深度, &候補深度)?;
    let (色の最大差, 色差画素数) = 色を比べる(&対照色, &候補色)?;
    Ok(format!(
        "mask完全一致・輪郭連結差0・深度の非数/無限大0({幾何画素数}幾何画素)、raw深度相補の最大差は単精度の隣接表現{相補の最大表現間隔数}段(診断値)、提示色最大差{色の最大差}階調・差画素{色差画素数}/{}",
        対照色.画素数()
    ))
}

fn 深度を読む(環境: &描画検収の実行環境, 名: &str) -> Result<Vec<u8>, 逆Z検収エラー> {
    Ok(環境.同じ置き場の書き出しのバイト列を読む(名前(名)?, 書き出しの形式::最終深度)?)
}

fn 名前(名: &str) -> Result<検収の実行名, 逆Z検収エラー> {
    Ok(検収の実行名::生成する(名)?)
}

fn 深度を比べる(対照: &深度画像, 候補: &深度画像) -> Result<(usize, u32), 逆Z検収エラー> {
    let mut 幾何画素数 = 0;
    let mut 相補の最大表現間隔数 = 0;
    for (対照値, 候補値) in 対照.深度列().iter().zip(候補.深度列()) {
        if !対照値.is_finite() || !候補値.is_finite() {
            return Err(逆Z検収エラー::判定が不合格("深度にNaNまたは無限大がある".to_string()));
        }
        let 対照幾何 = *対照値 < 1.0;
        let 候補幾何 = *候補値 > 0.0;
        if 対照幾何 != 候補幾何 {
            return Err(逆Z検収エラー::判定が不合格("背景とジオメトリのmaskが一致しない".to_string()));
        }
        if 対照幾何 {
            幾何画素数 += 1;
            let 対照の相補 = 1.0 - *対照値;
            相補の最大表現間隔数 = 相補の最大表現間隔数.max(対照の相補.to_bits().abs_diff(候補値.to_bits()));
        }
    }
    Ok((幾何画素数, 相補の最大表現間隔数))
}

fn 色を比べる(
    対照: &crate::acceptance::読み戻し画像, 候補: &crate::acceptance::読み戻し画像
) -> Result<(u8, usize), 逆Z検収エラー> {
    let mut 最大差 = 0;
    let mut 差画素数 = 0;
    for (左, 右) in 対照.画素列().zip(候補.画素列()) {
        let 画素の最大差 = 左.iter().zip(右).fold(0, |最大, (a, b)| 最大.max(a.abs_diff(*b)));
        最大差 = 最大差.max(画素の最大差);
        差画素数 += usize::from(画素の最大差 > 0);
    }
    if 最大差 > 1 || 差画素数.saturating_mul(色差画素の割合の分母) > 対照.画素数() {
        return Err(逆Z検収エラー::判定が不合格(format!(
            "提示色の差が上限を超えた(最大{最大差}階調、差画素{差画素数}/{})",
            対照.画素数()
        )));
    }
    Ok((最大差, 差画素数))
}
