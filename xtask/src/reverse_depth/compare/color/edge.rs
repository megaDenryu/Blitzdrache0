//! 深度の傾きから独立した二階差分と提示色の段差から、比較を免除する輪郭を作る工程。

use crate::acceptance::読み戻し画像;

use super::super::super::depth_image::{深度画像, 逆向き深度の奥行き};

// 24階調は植生と地形の勝者差を拾い、量子化と時間再構成の小差を輪郭にしない2000m実測の境界である。
const 色輪郭の下限: u8 = 24;
// 5cmは近景の単精度丸めを包み、奥行きの0.1%は遠景で同じ相対曲率を拾う。
const 深度輪郭の絶対下限メートル: f64 = 0.05;
const 深度輪郭の相対下限: f64 = 0.001;

pub(super) fn 輪郭画像を作る(色: &読み戻し画像, 深度: &深度画像) -> Vec<bool> {
    let 幅 = 色.幅().画素数();
    let 高さ = 色.高さ().画素数();
    (0..色.画素数()).map(|番号| 輪郭か(番号, 幅, 高さ, 色, 深度)).collect()
}

fn 輪郭か(番号: usize, 幅: usize, 高さ: usize, 色: &読み戻し画像, 深度: &深度画像) -> bool {
    let 横 = 番号 % 幅;
    let 縦 = 番号 / 幅;
    色の段差か(番号, 横, 縦, 幅, 高さ, 色) || 横の深度輪郭か(横, 縦, 幅, 深度) || 縦の深度輪郭か(横, 縦, 幅, 高さ, 深度)
}

fn 色の段差か(番号: usize, 横: usize, 縦: usize, 幅: usize, 高さ: usize, 色: &読み戻し画像) -> bool {
    隣接位置(横, 縦, 幅, 高さ).any(|隣| 画素差(&色.バイト列()[番号 * 4..番号 * 4 + 3], &色.バイト列()[隣 * 4..隣 * 4 + 3]) > 色輪郭の下限)
}

fn 横の深度輪郭か(横: usize, 縦: usize, 幅: usize, 深度: &深度画像) -> bool {
    横 > 0
        && 横 + 1 < 幅
        && 深度の二階差が輪郭か(
            深度.深度列()[縦 * 幅 + 横 - 1],
            深度.深度列()[縦 * 幅 + 横],
            深度.深度列()[縦 * 幅 + 横 + 1],
        )
}

fn 縦の深度輪郭か(横: usize, 縦: usize, 幅: usize, 高さ: usize, 深度: &深度画像) -> bool {
    縦 > 0
        && 縦 + 1 < 高さ
        && 深度の二階差が輪郭か(
            深度.深度列()[(縦 - 1) * 幅 + 横],
            深度.深度列()[縦 * 幅 + 横],
            深度.深度列()[(縦 + 1) * 幅 + 横],
        )
}

fn 深度の二階差が輪郭か(前: f32, 中: f32, 後: f32) -> bool {
    let 幾何 = [前 > 0.0, 中 > 0.0, 後 > 0.0];
    if 幾何.iter().any(|値| *値 != 幾何[0]) {
        return true;
    }
    if !幾何[0] {
        return false;
    }
    let [前, 中, 後] = [前, 中, 後].map(逆向き深度の奥行き);
    ((後 - 中) - (中 - 前)).abs() > 深度輪郭の絶対下限メートル.max(中 * 深度輪郭の相対下限)
}

fn 隣接位置(横: usize, 縦: usize, 幅: usize, 高さ: usize) -> impl Iterator<Item = usize> {
    let 一覧 = [
        横.checked_sub(1).map(|x| 縦 * 幅 + x),
        (横 + 1 < 幅).then_some(縦 * 幅 + 横 + 1),
        縦.checked_sub(1).map(|y| y * 幅 + 横),
        (縦 + 1 < 高さ).then_some((縦 + 1) * 幅 + 横),
    ];
    一覧.into_iter().flatten()
}

fn 画素差(左: &[u8], 右: &[u8]) -> u8 {
    左.iter().zip(右).fold(0, |最大, (a, b)| 最大.max(a.abs_diff(*b)))
}
