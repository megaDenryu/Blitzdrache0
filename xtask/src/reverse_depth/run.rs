//! 固定構図を提示色と最終深度へ別々に書き出す。

use std::path::PathBuf;

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 書き出しの形式, 検収の実行名, 検収エラー,
    検収シーン名,
};

const シーン: 検収シーン名 = 検収シーン名::生成する("terrain_origin");
const 枚数: 描画フレーム数 = 描画フレーム数::生成する(120);
const アセット: &str = "target/terrain_assets";
const 先読み半径の綴り: &str = "2";

pub(super) fn 実行環境を作る(出力先: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::構築済みのリリース版を直に起動する,
        実行時アセットルート::綴りから生成する(アセット),
        出力先,
    )
}

fn 起動指定() -> アプリの起動指定 {
    // 色を深度事前描画と同じ面だけへ等値比較で重ね、逆向き深度のEQUAL枝も本番の経路で検収する。
    アプリの起動指定::シーンと枚数を決める(シーン, 枚数)
        .選択肢を足す("--streaming")
        .値を持つ選択肢を足す("--streaming-preload-radius", 先読み半径の綴り)
        .値を持つ選択肢を足す("--streaming-ram-limit", "16777216")
        .値を持つ選択肢を足す("--streaming-vram-limit", "16777216")
        .値を持つ選択肢を足す("--camera-pitch", "-25")
        .値を持つ選択肢を足す("--time-of-day", "43200")
        .値を持つ選択肢を足す("--depth-prepass", "equal")
}

pub(super) fn 対照を採る(環境: &描画検収の実行環境) -> Result<(), 検収エラー> {
    撮る(環境, "reference_color", "reference_depth")
}

pub(super) fn 候補を採る(環境: &描画検収の実行環境) -> Result<(), 検収エラー> {
    撮る(環境, "candidate_color", "candidate_depth")
}

fn 撮る(環境: &描画検収の実行環境, 色名: &str, 深度名: &str) -> Result<(), 検収エラー> {
    環境.描いて読み戻す(検収の実行名::生成する(色名)?, &起動指定())?;
    環境.書き出させて報告を採る(検収の実行名::生成する(深度名)?, &起動指定(), 書き出しの形式::最終深度)?;
    let 再撮影名 = format!("{深度名}_repeat");
    環境.書き出させて報告を採る(検収の実行名::生成する(&再撮影名)?, &起動指定(), 書き出しの形式::最終深度)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::先読み半径の綴り;

    #[test]
    fn 常駐範囲は旧遠クリップの内側に収まる() {
        const チャンクの一辺メートル: f32 = 100.0;
        const 地形と視点の垂直差の保守上限メートル: f32 = 200.0;
        const 旧遠クリップメートル: f32 = 2000.0;
        let 先読み半径 = 先読み半径の綴り.parse::<f32>().unwrap_or(f32::INFINITY);
        let 常駐範囲の水平上限 = (先読み半径 + 1.0) * チャンクの一辺メートル * std::f32::consts::SQRT_2;
        // 地形の振幅9.5mと検収カメラの距離150mを足した159.5mを上回る200mで包む。
        let 全方向の上限 = 常駐範囲の水平上限.hypot(地形と視点の垂直差の保守上限メートル);
        assert!(全方向の上限 < 旧遠クリップメートル, "常駐範囲の上限{全方向の上限}mが旧遠クリップ内にない");
    }
}
