//! 前後が標準Zの同じ表現へ潰れる合成面を重ね、逆向き深度だけが前面色を守ることを反証する。

use super::depth_image::{標準投影の深度, 逆向き投影の深度};
use super::error::逆Z検収エラー;

const 前面距離: f32 = 1000.0;
const 背面距離: f32 = 1000.01;
const 前面色: [u8; 3] = [31, 104, 64];
const 背面色: [u8; 3] = [163, 175, 193];

pub(super) fn 前面色の保持を反証する() -> Result<String, 逆Z検収エラー> {
    let 標準前面 = 標準投影の深度(前面距離);
    let 標準背面 = 標準投影の深度(背面距離);
    let 逆向き前面 = 逆向き投影の深度(前面距離);
    let 逆向き背面 = 逆向き投影の深度(背面距離);
    let 標準色 = 前面の後に背面を描く(標準前面, 標準背面, |新, 済| 新 <= 済);
    let 逆向き色 = 前面の後に背面を描く(逆向き前面, 逆向き背面, |新, 済| 新 >= 済);
    if 標準前面 != 標準背面 || 標準色 != 背面色 || 逆向き前面 <= 逆向き背面 || 逆向き色 != 前面色 {
        return Err(逆Z検収エラー::判定が不合格(format!(
            "合成重なりの前面色反証が不成立(標準深度{標準前面:.9}/{標準背面:.9}、逆向き深度{逆向き前面:.9}/{逆向き背面:.9})"
        )));
    }
    Ok(format!("合成重なり{前面距離:.2}m/{背面距離:.2}mは標準Zで同値、逆向き深度で前面色を保持"))
}

fn 前面の後に背面を描く(前面深度: f32, 背面深度: f32, 通るか: impl Fn(f32, f32) -> bool) -> [u8; 3] {
    if 通るか(背面深度, 前面深度) { 背面色 } else { 前面色 }
}

