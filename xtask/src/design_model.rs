//! 設計意味の抽出と設計関係グラフの組み立て(Issue #170。層1と層2)。
//!
//! Rustのソースの構文と、`blitz_design` の設計解釈マーカーと、関数の役割の型引数の組から、設計上の関係を抽出する。
//! 抽出してよい構文は `relation.rs` の `抽出元の構文` が数え上げた5つだけであり、生の `fn f(a: A) -> B` からは何も抽出しない。
//!
//! **この木は検証系の信頼基盤である。** 抽出が誤ったDグラフを作れば、その上で示した命題の成立は意味を持たない。
//! そのため抽出の規則1つごとに「このRustの構文からこの関係が出る」を固定する回帰試験を置く。
//! 構文の読み取りは `super::conform::design_ontology` の構文解析器(`型の定義を探す`・`モジュールパス`・`クレート構文検査`)を借り、複製を作らない。
//! 節点の識別子のモジュールパスが空であることは、その型の定義をたどれなかった(未解決である)ことを表す取り決めである。
//! 未解決の節点を落とさないのは、落とすと「関係が無い」と読まれて偽の反証が出るためであり、そのとき抽出器は同じ1件を `抽出できなかった行` として数える。
//! 参照: `_doc/設計/設計オントロジー.md` 第6節。

mod concept;
mod extract;
mod relation;
mod relation_graph;

pub use concept::{設計概念, 設計概念の種類, 設計概念の識別子};
pub use extract::{抽出できなかった理由, 抽出できなかった行, 抽出の結末, 設計関係グラフを抽出する};
pub use relation::{抽出の出どころ, 抽出元の構文, 設計関係, 設計関係の種類};
pub use relation_graph::設計関係グラフ;
