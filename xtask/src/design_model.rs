//! Rustのソースから設計関係グラフを抽出する木(Issue #170。層1と層2の抽出)。
//!
//! Rustのソースの構文と、`blitz_design` の設計解釈マーカーと、関数の役割の型引数の組から、設計上の関係と分類の事実を抽出する。
//! 設計関係を抽出してよい構文は `抽出元の構文` が数え上げた4つだけであり、生の `fn f(a: A) -> B` からは何も抽出しない。
//! マーカーの実装と上位トレイトの宣言からは設計関係を出さず、分類の事実(`blitz_design_verification::分類の事実`)を出す。
//!
//! **この木は検証系の信頼基盤である。** 抽出が誤ったDグラフを作れば、その上で示した命題の成立は意味を持たない。
//! そのため抽出の規則1つごとに「このRustの構文からこの関係が出る」を固定する回帰試験を置く。
//! 構文の読み取りは `super::conform::design_ontology` の構文解析器(`型の定義を探す`・`モジュールパス`・`クレート構文検査`)を借り、複製を作らない。
//! Rustの項目の名前空間の節点で、識別子のモジュールパスが空であることは、その型の定義をたどれなかった(未解決である)ことを表す取り決めである。
//! 未解決の節点を落とさないのは、落とすと「関係が無い」と読まれて偽の反証が出るためであり、そのとき抽出器は同じ1件を `抽出できなかった行` として数える。
//!
//! 設計概念・設計関係・設計関係グラフの型そのものは `blitz_design_verification` が所有する。`xtask` はそれらを組み立てる側であり、
//! ここで再公開するのは、抽出の側の利用箇所がグラフの語彙をこの木の名前で読めるようにするためである。
//! 参照: `_doc/設計/設計オントロジー.md` 第6節。

