//! 2実行の観測から合否を決める工程。受け取るのは2つの観測、返すのは判定の結果である。
//!
//! 判定は3つだけである。履歴を無効にした直後の1フレーム目が今のフレームの色と画素で一致すること、
//! 同じ条件の2実行が同じ要約値を出すこと、観測した差分が1本でも非有限でないことである。
//! フレーム間差分の大きさそのものは判定に使わない。閾値をまだ制定していないためである
//! (`参照: _doc/設計/時間再構成.md`「検収戦略(判断g)」の3)。

use super::observation::観測;

pub(super) fn 判定する(一回目: &観測, 二回目: &観測) -> Result<(), String> {
    無効化直後の一致を見る(一回目)?;
    無効化直後の一致を見る(二回目)?;
    if 一回目.ダイジェスト != 二回目.ダイジェスト {
        return Err(format!(
            "同じ条件の2実行が違う結果を出した(1回目のダイジェスト{}・2回目{})",
            一回目.ダイジェスト, 二回目.ダイジェスト
        ));
    }
    差分が有限であることを見る(一回目, "1回目")?;
    差分が有限であることを見る(二回目, "2回目")
}

/// 判断cの規律を画素で反証する。混ぜてから捨てる形になっていれば、丸め誤差の分だけ画素が食い違う。
fn 無効化直後の一致を見る(観測: &観測) -> Result<(), String> {
    if 観測.無効化直後の不一致画素数 != 0 {
        return Err(format!(
            "履歴を無効にした直後の結果が今のフレームの色と一致しない(全画素{}のうち{}画素・最大差{:.9})",
            観測.全画素数, 観測.無効化直後の不一致画素数, 観測.無効化直後の最大差
        ));
    }
    Ok(())
}

/// 差分が非有限になるのは、履歴に非数が入って以後どれだけ混ぜても消えない状態である。
fn 差分が有限であることを見る(観測: &観測, 呼び名: &str) -> Result<(), String> {
    if !観測.差分の最大.is_finite() {
        return Err(format!("{呼び名}のフレーム間差分に非有限の値が現れた(最大{})", 観測.差分の最大));
    }
    Ok(())
}
