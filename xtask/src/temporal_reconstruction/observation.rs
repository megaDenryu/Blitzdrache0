//! blitz_appが出した時間再構成の行を数の並びへ直す工程。受け取るのは標準出力と実行の呼び名、返すのは1実行ぶんの観測である。
//!
//! 行が1本も無いことを失敗にするのは、観測が1度も走らなかった実行を「差が無かった」と読み替えないためである。
//! 見送りの行も同じ理由で失敗にする。

mod parse;

use parse::{一行を探す, 字面を読む, 小数を読む, 数を読む};

/// 1実行ぶんの観測。判定は`judgment`が持ち、この型は数だけを運ぶ。
pub(super) struct 観測 {
    /// 履歴を無効にした直後の結果と今のフレームの色の、成分ごとの差の絶対値の最大。
    pub(super) 無効化直後の最大差: f64,
    /// その突き合わせで1ビットでも違った画素の数。
    pub(super) 無効化直後の不一致画素数: u64,
    pub(super) 全画素数: u64,
    /// 再構成後の画像1枚を畳んだ要約値。2実行の一致が決定性である。
    pub(super) ダイジェスト: String,
    /// 観測した全フレームのフレーム間差分の最大。
    pub(super) 差分の最大: f64,
    /// 最後の1周ぶんのフレーム間差分の最大。周期軌道へ入った後の揺れの大きさである。
    pub(super) 最後の一周の差分の最大: f64,
    pub(super) 差分の観測本数: usize,
}

const 見出し: &str = "[temporal-reconstruction]";

pub(super) fn 取り出す(標準出力: &str, 呼び名: &str) -> Result<観測, String> {
    let 行一覧: Vec<&str> = 標準出力.lines().filter(|行| 行.contains(見出し)).collect();
    if let Some(行) = 行一覧.iter().find(|行| 行.contains("見送った")) {
        return Err(format!("{呼び名}で読み戻しが見送られた: {行}"));
    }
    let 無効化直後 = 一行を探す(&行一覧, "無効化直後", 呼び名)?;
    let 要約 = 一行を探す(&行一覧, "要約", 呼び名)?;
    let 列の長さ = 数を読む(一行を探す(&行一覧, "列の長さ", 呼び名)?, "列の長さ", 呼び名)?;
    let 差分一覧 = 差分の列を読む(&行一覧, 呼び名)?;
    if 差分一覧.is_empty() {
        return Err(format!("{呼び名}にフレーム間差分の行が1本も無い"));
    }
    Ok(観測 {
        無効化直後の最大差: 小数を読む(無効化直後, "最大差", 呼び名)?,
        無効化直後の不一致画素数: 数を読む(無効化直後, "一致しない画素", 呼び名)?,
        全画素数: 数を読む(無効化直後, "全画素", 呼び名)?,
        ダイジェスト: 字面を読む(要約, "ダイジェスト", 呼び名)?,
        差分の最大: 最大を採る(&差分一覧),
        最後の一周の差分の最大: 最大を採る(最後の一周(&差分一覧, 列の長さ)),
        差分の観測本数: 差分一覧.len(),
    })
}

pub(super) fn 要約を組む(観測: &観測) -> String {
    format!(
        "無効化直後は全画素{}のうち一致しない画素{}(最大差{:.9})、2実行のダイジェストは{}で一致、フレーム間差分は{}本の観測で最大{:.9}・最後の1周で最大{:.9}",
        観測.全画素数,
        観測.無効化直後の不一致画素数,
        観測.無効化直後の最大差,
        観測.ダイジェスト,
        観測.差分の観測本数,
        観測.差分の最大,
        観測.最後の一周の差分の最大
    )
}

fn 最後の一周(差分一覧: &[f64], 列の長さ: u64) -> &[f64] {
    let 本数 = usize::try_from(列の長さ).unwrap_or(差分一覧.len()).min(差分一覧.len());
    &差分一覧[差分一覧.len() - 本数..]
}

fn 最大を採る(差分一覧: &[f64]) -> f64 {
    差分一覧.iter().copied().fold(0.0, f64::max)
}

fn 差分の列を読む(行一覧: &[&str], 呼び名: &str) -> Result<Vec<f64>, String> {
    行一覧
        .iter()
        .filter(|行| 行.contains("フレーム間差分"))
        .map(|行| 小数を読む(行, "最大", 呼び名))
        .collect()
}
