//! blitz_appが出した時間再構成の行を数の並びへ直す工程。受け取るのは終了時報告、返すのは1実行ぶんの観測である。
//!
//! 行が1本も無いことを失敗にするのは、観測が1度も走らなかった実行を「差が無かった」と読み替えないためである。
//! 見送りの行も同じ理由で失敗にする。見送りの探し方と鍵に結ばれた数の読み方は`report_line`が持つ。

use super::report_line::{数を読む, 見送りが無いことを確かめる};
use crate::acceptance::{判定の名前, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

/// 1実行ぶんの観測。判定は`judgment`が持ち、この型は数だけを運ぶ。
pub(super) struct 観測 {
    /// 履歴を無効にした直後の結果と今のフレームの色の、成分ごとの差の絶対値の最大。
    pub(super) 無効化直後の最大差: f64,
    /// その突き合わせで1ビットでも違った画素の数。
    pub(super) 無効化直後の不一致画素数: u64,
    pub(super) 全画素数: u64,
    /// 再構成後の画像1枚を畳んだ要約値。2実行の一致が決定性である。
    pub(super) ダイジェスト: String,
    /// 観測した全フレームのフレーム間差分の最大。
    pub(super) 差分の最大: f64,
    /// 最後の1周ぶんのフレーム間差分の最大。周期軌道へ入った後の揺れの大きさである。
    pub(super) 最後の一周の差分の最大: f64,
    pub(super) 差分の観測本数: usize,
}

const 無効化直後の見出し: 報告の見出し = 報告の見出し::定数から生成する("[temporal-reconstruction] 無効化直後");
const 要約の見出し: 報告の見出し = 報告の見出し::定数から生成する("[temporal-reconstruction] 要約");
const 列の長さの見出し: 報告の見出し = 報告の見出し::定数から生成する("[temporal-reconstruction] 列の長さ");
const フレーム間差分の見出し: 報告の見出し = 報告の見出し::定数から生成する("[temporal-reconstruction] フレーム間差分");
/// 要約の行は「ダイジェスト0a1b…」と1語に続くため、鍵の後ろの残りを十六進の綴りとして採る。
const ダイジェストの鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("ダイジェスト");
const フレーム間差分の行: 判定の名前 = 判定の名前::定数から生成する("フレーム間差分の行");

pub(super) fn 取り出す(報告: &終了時報告) -> Result<観測, 検収エラー> {
    見送りが無いことを確かめる(報告, "再構成の観測")?;
    let 無効化直後 = 報告.見出しの1行(&無効化直後の見出し)?;
    let 列の長さ = 報告.見出しに続く数(&列の長さの見出し)?;
    let 差分一覧 = 差分の列を読む(報告)?;
    if 差分一覧.is_empty() {
        return Err(フレーム間差分の行.あるはずのものが無い破れ().into());
    }
    Ok(観測 {
        無効化直後の最大差: 数を読む(&無効化直後, "最大差")?,
        無効化直後の不一致画素数: 数を読む(&無効化直後, "一致しない画素")?,
        全画素数: 数を読む(&無効化直後, "全画素")?,
        ダイジェスト: 報告
            .見出しの1行(&要約の見出し)?
            .鍵に結ばれた綴り(&ダイジェストの鍵, 鍵に値が結ばれる形::この綴りに続く残りが値である)?,
        差分の最大: 最大を採る(&差分一覧),
        最後の一周の差分の最大: 最大を採る(最後の一周(&差分一覧, 列の長さ)),
        差分の観測本数: 差分一覧.len(),
    })
}

pub(super) fn 要約を組む(観測: &観測) -> String {
    format!(
        "無効化直後は全画素{}のうち一致しない画素{}(最大差{:.9})、2実行のダイジェストは{}で一致、フレーム間差分は{}本の観測で最大{:.9}・最後の1周で最大{:.9}",
        観測.全画素数,
        観測.無効化直後の不一致画素数,
        観測.無効化直後の最大差,
        観測.ダイジェスト,
        観測.差分の観測本数,
        観測.差分の最大,
        観測.最後の一周の差分の最大
    )
}

fn 差分の列を読む(報告: &終了時報告) -> Result<Vec<f64>, 検収エラー> {
    報告
        .見出しで始まる行の一覧(&フレーム間差分の見出し)
        .iter()
        .map(|行| 数を読む(行, "最大"))
        .collect()
}

fn 最後の一周(差分一覧: &[f64], 列の長さ: u64) -> &[f64] {
    let 本数 = usize::try_from(列の長さ).unwrap_or(差分一覧.len()).min(差分一覧.len());
    &差分一覧[差分一覧.len() - 本数..]
}

fn 最大を採る(差分一覧: &[f64]) -> f64 {
    差分一覧.iter().copied().fold(0.0, f64::max)
}
