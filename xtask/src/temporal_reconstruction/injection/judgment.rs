//! 合成入力の突き合わせに課す判定と、その許容の台帳。受け取るのは観測、返すのは合否である。
//!
//! 許容を相対の差で置くのは、この差の出どころが再構成後の色を半精度の画像へ書くときの丸めだからである。
//! 半精度の刻みは値の大きさに比例するため、絶対の差で縛ると明るい画素で緩く暗い画素で厳しい1つの値しか選べない。
//!
//! **許容の根拠**: 半精度の隣り合う表現の間隔は、値に対して最大で2の-10乗(約0.000977)である。CPU正本は単精度で
//! 計算した値を持ち、GPUはその値を半精度へ丸めて書くため、2つの差はこの間隔1つぶんまで開きうる。単精度の演算の
//! 食い違い(相対2の-24乗)はこれより6桁小さく、合成の順を写しと揃えてある以上さらに小さい。
//! 契約はこの原理から導いた上限へ余白を4倍取った2の-8乗である。**実測はこの値でなく、原理の側から置いた。**
//! 2026-08-08の実測(1280x720・全画素921600)は最大の相対差0.000950034であり、原理の上限0.000977のすぐ内側にある。
//! 実測をそのまま契約へ昇格させると、値が原理の上限へ触れただけで検収が落ちる。
//!
//! 枝の件数を見るのは、差が小さいことだけでは「1つの枝しか通っていない」状態と区別できないためである。

use super::注入の観測;
use crate::acceptance::{判定の名前, 判定の破れ};

/// 半精度の隣り合う表現の相対の間隔の上限(2の-10乗)へ、余白を4倍取った値。
pub(super) const 相対の許容: f64 = 0.003_906_25;

/// 合成入力が通す3つの枝。並びは観測の枝別の画素数と同じである。
const 枝の名前: [&str; 3] = ["履歴を採る", "出現領域", "画面の外"];

const 枝別の画素数の和: 判定の名前 = 判定の名前::定数から生成する("合成入力の突き合わせの枝別の画素数の和");

pub(super) fn 判定する(観測: &注入の観測) -> Result<(), 判定の破れ> {
    let 相対差 = 相対差の判定名(観測);
    相対差.有限であることを課す(観測.最大の相対差)?;
    相対差.上限を課す(観測.最大の相対差, 相対の許容)?;
    for (枝, 件数) in 枝の名前.iter().zip(観測.枝別の画素数) {
        if 件数 == 0 {
            return Err(枝の判定名(枝).あるはずのものが無い破れ());
        }
    }
    枝別の画素数の和.一致を課す(観測.枝別の画素数.iter().sum::<u64>(), 観測.全画素数)
}

/// 最大の絶対差を綴りへ入れるのは、相対差に課す判定が同じ行の絶対差を文面へ出せないためである。
fn 相対差の判定名(観測: &注入の観測) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("合成入力の突き合わせの最大の相対差(最大の絶対差{:.9})", 観測.最大の絶対差))
}

fn 枝の判定名(枝: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{枝}の枝を通った画素(1つも無いのは合成入力の焼き方の誤りである)"))
}
