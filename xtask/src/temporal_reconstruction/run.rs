//! 1回ぶんの起動の指定と、その実行の報告の採取。受け取るのは実行の呼び名、返すのはその実行の報告である。
//!
//! 目視見本の庭を使うのは、この世界が時間再構成方式に履歴混合を宣言しており、パスが実際に積まれる世界そのもの
//! だからである。空も自動露出もポスト処理も本番の経路のまま残すのは、再構成が読む色が本番の絵と同じ
//! HDR中間画像の中身だからである。
//!
//! フレーム数を目視見本と同じ本数に採るのは、空と間接照明の焼き上げが定常へ入った状態で観測するためである。
//! 焼き上げが進んでいる間はフレーム間差分が再構成と無関係な要因で動く。

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 世界を読ませて報告を採る実行環境, 描画フレーム数, 検収の実行名
};
use crate::visual_sample_world::{目視見本世界のアセットルートを作る, 目視見本世界のシーン名};

/// 描くフレーム数。`terrain-visual`と同じ本数である。
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(120);
/// 正午。時刻を1つに固定して、読み手が条件を推測しなくてよいようにする。
const 一日内秒: &str = "43200";
/// 合成入力の突き合わせの本数。履歴を有効にする1枚と突き合わせる1枚が最終フレームで走るため、そこまで進めば足りる。
const 注入のフレーム数: 描画フレーム数 = 描画フレーム数::生成する(12);

pub(super) fn 実行環境を作る() -> 世界を読ませて報告を採る実行環境 {
    世界を読ませて報告を採る実行環境::作る(アプリの起こし方::毎回cargoに構築させて起動する, 目視見本世界のアセットルートを作る())
}

pub(super) fn 観測を採る(
    実行環境: &世界を読ませて報告を採る実行環境, 実行名: 検収の実行名, 呼び名: &str
) -> Result<String, String> {
    走らせる(実行環境, 実行名, 呼び名, フレーム数, "--report-temporal-reconstruction")
}

/// 合成入力の突き合わせの1回。焼き上げの進み具合に依存しないため短い本数で足りる。4枚とも検収が決めた値へ
/// 差し替わるため、空も間接照明も結果へ1画素も現れない。
pub(super) fn 合成入力の観測を採る(実行環境: &世界を読ませて報告を採る実行環境) -> Result<String, String> {
    走らせる(
        実行環境,
        合成入力の実行名,
        "合成入力の突き合わせ",
        注入のフレーム数,
        "--report-temporal-reconstruction-injection",
    )
}

/// 3回の実行の書き出しの基準名。絵は書き出さないが、失敗の文面がどの実行かを名指すために要る。
pub(super) const 一回目の実行名: 検収の実行名 = 検収の実行名::定数から生成する("first");
pub(super) const 二回目の実行名: 検収の実行名 = 検収の実行名::定数から生成する("second");
const 合成入力の実行名: 検収の実行名 = 検収の実行名::定数から生成する("injection");

fn 走らせる(
    実行環境: &世界を読ませて報告を採る実行環境,
    実行名: 検収の実行名,
    呼び名: &str,
    描くフレーム数: 描画フレーム数,
    報告の指定: &str,
) -> Result<String, String> {
    println!("[xtask] temporal-reconstruction実行: {呼び名}");
    let 指定 = アプリの起動指定::シーンと枚数を決める(目視見本世界のシーン名, 描くフレーム数)
        .値を持つ選択肢を足す("--time-of-day", 一日内秒)
        .選択肢を足す(報告の指定);
    Ok(実行環境.報告を採る(実行名, &指定)?.本文().to_string())
}
