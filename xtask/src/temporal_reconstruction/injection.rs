//! 合成入力の突き合わせの行を読み、その値を運ぶ工程。受け取るのは終了時報告、返すのは1実行ぶんの観測である。
//! 許容と合否は`judgment`が持つ。
//!
//! 行が1本も無いことを失敗にするのは、突き合わせが1度も走らなかった実行を「差が無かった」と読み替えないためである。
//! 見送りの行も同じ理由で失敗にする。見送りの探し方と鍵に結ばれた数の読み方は`report_line`が持つ。

mod judgment;

use super::report_line::{数を読む, 見送りが無いことを確かめる};
use crate::acceptance::{検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;

const 突き合わせの見出し: 報告の見出し = 報告の見出し::定数から生成する("[temporal-reconstruction] 合成入力の突き合わせ");

/// 1実行ぶんの突き合わせの観測。
pub(super) struct 注入の観測 {
    pub(super) 全画素数: u64,
    pub(super) 最大の絶対差: f64,
    pub(super) 最大の相対差: f64,
    pub(super) 枝別の画素数: [u64; 3], // 履歴を採る枝・出現領域の枝・画面の外の枝の画素数
}

pub(super) fn 取り出して判定する(報告: &終了時報告) -> Result<注入の観測, 検収エラー> {
    見送りが無いことを確かめる(報告, "合成入力の突き合わせ")?;
    let 行 = 報告.見出しの1行(&突き合わせの見出し)?;
    let 観測 = 注入の観測 {
        全画素数: 数を読む(&行, "全画素")?,
        最大の絶対差: 数を読む(&行, "最大の絶対差")?,
        最大の相対差: 数を読む(&行, "最大の相対差")?,
        枝別の画素数: [
            数を読む(&行, "履歴を採る画素")?,
            数を読む(&行, "出現領域の画素")?,
            数を読む(&行, "画面の外の画素")?,
        ],
    };
    judgment::判定する(&観測)?;
    Ok(観測)
}

pub(super) fn 要約を組む(観測: &注入の観測) -> String {
    format!(
        "合成入力の突き合わせは全画素{}で最大の相対差{:.9}(許容{:.9})・最大の絶対差{:.9}、枝別の画素数は履歴を採る{}・出現領域{}・画面の外{}",
        観測.全画素数,
        観測.最大の相対差,
        judgment::相対の許容,
        観測.最大の絶対差,
        観測.枝別の画素数[0],
        観測.枝別の画素数[1],
        観測.枝別の画素数[2]
    )
}
