//! 合成入力の突き合わせの行を読み、許容の内側かを判定する工程。受け取るのは標準出力、返すのは観測か失敗である。
//!
//! 許容を相対の差で置くのは、この差の出どころが再構成後の色を半精度の画像へ書くときの丸めだからである。
//! 半精度の刻みは値の大きさに比例するため、絶対の差で縛ると明るい画素で緩く暗い画素で厳しい1つの値しか選べない。
//!
//! **許容の根拠**: 半精度の隣り合う表現の間隔は、値に対して最大で2の-10乗(約0.000977)である。CPU正本は単精度で
//! 計算した値を持ち、GPUはその値を半精度へ丸めて書くため、2つの差はこの間隔1つぶんまで開きうる。単精度の演算の
//! 食い違い(相対2の-24乗)はこれより6桁小さく、合成の順を写しと揃えてある以上さらに小さい。
//! 契約はこの原理から導いた上限へ余白を4倍取った2の-8乗である。**実測はこの値でなく、原理の側から置いた。**
//! 2026-08-08の実測(1280x720・全画素921600)は最大の相対差0.000950034であり、原理の上限0.000977のすぐ内側にある。
//! 実測をそのまま契約へ昇格させると、値が原理の上限へ触れただけで検収が落ちる。

/// 半精度の隣り合う表現の相対の間隔の上限(2の-10乗)へ、余白を4倍取った値。
const 相対の許容: f64 = 0.003_906_25;

const 見出し: &str = "[temporal-reconstruction] 合成入力の突き合わせ";

/// 1実行ぶんの突き合わせの観測。
pub(super) struct 注入の観測 {
    pub(super) 全画素数: u64,
    pub(super) 最大の絶対差: f64,
    pub(super) 最大の相対差: f64,
    /// 履歴を採る枝・出現領域の枝・画面の外の枝の画素数。
    pub(super) 枝別の画素数: [u64; 3],
}

pub(super) fn 取り出して判定する(標準出力: &str) -> Result<注入の観測, String> {
    let 行 = 標準出力
        .lines()
        .find(|行| 行.contains(見出し))
        .ok_or_else(|| "合成入力の突き合わせの行が無い".to_string())?;
    if 行.contains("見送った") {
        return Err(format!("合成入力の突き合わせで読み戻しが見送られた: {行}"));
    }
    let 観測 = 注入の観測 {
        全画素数: 数を読む(行, "全画素")?,
        最大の絶対差: 小数を読む(行, "最大の絶対差")?,
        最大の相対差: 小数を読む(行, "最大の相対差")?,
        枝別の画素数: [
            数を読む(行, "履歴を採る画素")?,
            数を読む(行, "出現領域の画素")?,
            数を読む(行, "画面の外の画素")?,
        ],
    };
    判定する(&観測)?;
    Ok(観測)
}

pub(super) fn 要約を組む(観測: &注入の観測) -> String {
    format!(
        "合成入力の突き合わせは全画素{}で最大の相対差{:.9}(許容{相対の許容:.9})・最大の絶対差{:.9}、枝別の画素数は履歴を採る{}・出現領域{}・画面の外{}",
        観測.全画素数, 観測.最大の相対差, 観測.最大の絶対差, 観測.枝別の画素数[0], 観測.枝別の画素数[1], 観測.枝別の画素数[2]
    )
}

/// 差が許容の内側であることと、3つの枝がすべて画面に現れていることを見る。
/// 枝の件数を見るのは、差が小さいことだけでは「1つの枝しか通っていない」状態と区別できないためである。
fn 判定する(観測: &注入の観測) -> Result<(), String> {
    if !観測.最大の相対差.is_finite() || 観測.最大の相対差 > 相対の許容 {
        return Err(format!(
            "合成入力の突き合わせの最大の相対差{:.9}が許容{相対の許容:.9}を超えた(最大の絶対差{:.9})",
            観測.最大の相対差, 観測.最大の絶対差
        ));
    }
    let 名前 = ["履歴を採る", "出現領域", "画面の外"];
    for (位置, 件数) in 観測.枝別の画素数.iter().enumerate() {
        if *件数 == 0 {
            return Err(format!("{}の枝を通った画素が1つも無い(合成入力の焼き方の誤り)", 名前[位置]));
        }
    }
    let 合計: u64 = 観測.枝別の画素数.iter().sum();
    if 合計 != 観測.全画素数 {
        return Err(format!("枝別の画素数の和{合計}が全画素{}と違う", 観測.全画素数));
    }
    Ok(())
}

fn 数を読む(行: &str, 語: &str) -> Result<u64, String> {
    字面を読む(行, 語)?
        .parse()
        .map_err(|誤り| format!("合成入力の突き合わせの{語}を整数として読めない: {誤り}"))
}

fn 小数を読む(行: &str, 語: &str) -> Result<f64, String> {
    字面を読む(行, 語)?
        .parse()
        .map_err(|誤り| format!("合成入力の突き合わせの{語}を小数として読めない: {誤り}"))
}

fn 字面を読む(行: &str, 語: &str) -> Result<String, String> {
    let 残り = 行
        .split_once(語)
        .map(|(_, 後ろ)| 後ろ)
        .ok_or_else(|| format!("合成入力の突き合わせの行に{語}が無い: {行}"))?;
    let 字面: String = 残り.chars().take_while(|文字| 文字.is_ascii_digit() || *文字 == '.').collect();
    if 字面.is_empty() {
        return Err(format!("合成入力の突き合わせの{語}に続く数が読めない: {行}"));
    }
    Ok(字面)
}
