//! この入口が読む報告の行に共通する語彙と読み取り。受け取るのは終了時報告か報告の行、
//! 返すのは見送りの有無と、鍵に結ばれた数である。
//!
//! 再構成の観測と合成入力の突き合わせが同じものを使うのは、どちらも同じ報告の同じ書式の行を読むためである。
//! 見送りの見出しと値の結ばれ方を2箇所に持つと、書式が変わったときに片方だけが静かに読めなくなる。

use crate::acceptance::{判定の名前, 判定の破れ, 報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

/// 読み戻しが成立しなかった実行が出す行。正本は`crates/blitz_app/src/reports/temporal_reconstruction.rs`である。
const 見送りの見出し: 報告の見出し = 報告の見出し::定数から生成する("[temporal-reconstruction] 読み戻しを見送った");
/// この報告の行は読点で区切り、鍵に数がそのまま続く。
const 値の結ばれ方: 鍵に値が結ばれる形 = 鍵に値が結ばれる形::この綴りに続く数字の並びが値である;

/// 見送りの行が1本も無いことを確かめる。見送りを別の見出しで探すのは、見送りの行が他の項目を1つも
/// 持たないためである。同じ行を鍵で読もうとすると「読み戻しが見送られた」でなく「全画素の鍵が無い」で落ちる。
///
/// 見送りの行そのものを判定の名前へ入れるのは、blitz_appが見送った理由をその行に書いているためである。
pub(super) fn 見送りが無いことを確かめる(報告: &終了時報告, 何の観測か: &str) -> Result<(), 判定の破れ> {
    let 行一覧 = 報告.見出しで始まる行の一覧(&見送りの見出し);
    let 行の綴り = 行一覧.first().map_or_else(String::new, |行| 行.原文().to_string());
    判定の名前::組み立てた綴りから生成する(format!("{何の観測か}の読み戻しの見送り(行「{行の綴り}」)")).零件であることを課す(行一覧.len())
}

pub(super) fn 数を読む<数: std::str::FromStr>(行: &報告の行, 鍵の綴り: &str) -> Result<数, 検収エラー> {
    行.鍵に結ばれた数(&報告の行の鍵::組み立てた綴りから生成する(鍵の綴り.to_string()), 値の結ばれ方)
}
