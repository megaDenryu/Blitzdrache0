//! アプリの終了時報告から検収が使う数を取り出す工程。受け取るのは標準出力、返すのはパス別の描画発行と可視個体の選別の計数と確保数である。
//! 行の綴りは`crates/blitz_app/src/reports/draw_issue.rs`の出力と一致させている。
//! パスはシーンと距離区分0から距離区分3の5つであり、距離区分ごとに同じ5行の組が出る
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」)。
//! 行から値を取り出す工程は`line_read`にある。

mod line_read;

use line_read::{値を読む, 添字付きの数を読む};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct パス別描画発行 {
    pub 発行数: u64,
    pub 候補数: u64,
    pub 可視数: u64,
    pub 個体数: u64,
    /// 段番号ごとの個体数。添字が段番号であり、報告の行に現れた段までを持つ。
    pub 段別個体数: Vec<u64>,
}

/// 距離区分の数。レンダラーの`距離区分数`と同じ値であり、報告の行がこの数だけ並ぶ。
pub const 距離区分数: usize = 4;

/// 可視個体の選別がフレーム全体で数えた計数。レンダラー側の描画発行とは出どころが違い、2つの一致が整合の証拠になる。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 可視個体の選別の計数 {
    pub 候補数: u64,
    pub 個体判定数: u64,
    pub シーン可視数: u64,
    pub 距離区分別の可視数: Vec<u64>,
    /// 1つ以上の距離区分へ影を落とした個体の数。距離区分別の可視数の和と違い、複数の距離区分へ属する同じ個体を重複して数えない。
    pub 距離区分の和集合の可視数: u64,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 計数報告 {
    pub シーン: パス別描画発行,
    /// 距離区分0から距離区分3の描画発行。添字が距離区分番号である。
    pub 距離区分別のシャドウ: Vec<パス別描画発行>,
    pub 可視個体の選別: 可視個体の選別の計数,
    pub 現在確保数: u64,
    pub 最大同時確保数: u64,
    pub 段切替回数: u64,
    /// 可視判定と段選択へ登録されている群の件数。束の解除で材料と段の記憶が残っていないことをこの数で見る。
    pub 可視材料登録数: u64,
    pub 起動後シーン読込回数: u64,
    pub validation件数: u64,
}

/// シーンと距離区分0から距離区分3を名前付きで並べる。どのパスにも同じ条件を掛ける判定がこの走査を使う。
pub fn 全パスを並べる(計数: &計数報告) -> Vec<(String, &パス別描画発行)> {
    let mut 一覧 = vec![("シーンパス".to_string(), &計数.シーン)];
    for (番号, パス) in 計数.距離区分別のシャドウ.iter().enumerate() {
        一覧.push((format!("シャドウ距離区分{番号}"), パス));
    }
    一覧
}

pub fn 取り出す(標準出力: &str) -> Result<計数報告, String> {
    let mut 距離区分別のシャドウ = Vec::with_capacity(距離区分数);
    for 番号 in 0..距離区分数 {
        距離区分別のシャドウ.push(パス別を読む(標準出力, &format!("シャドウ距離区分{番号}"))?);
    }
    Ok(計数報告 {
        シーン: パス別を読む(標準出力, "シーン")?,
        距離区分別のシャドウ,
        可視個体の選別: 可視個体の選別を読む(標準出力)?,
        現在確保数: 値を読む(標準出力, "現在確保数:")?,
        最大同時確保数: 値を読む(標準出力, "最大同時確保数:")?,
        段切替回数: 値を読む(標準出力, "個体LOD段切替回数:")?,
        可視材料登録数: 値を読む(標準出力, "可視材料登録数:")?,
        起動後シーン読込回数: 値を読む(標準出力, "起動後シーン読込回数:")?,
        validation件数: 値を読む(標準出力, "validationエラー・警告合計件数:")?,
    })
}

fn 可視個体の選別を読む(標準出力: &str) -> Result<可視個体の選別の計数, String> {
    Ok(可視個体の選別の計数 {
        候補数: 値を読む(標準出力, "選別候補数:")?,
        個体判定数: 値を読む(標準出力, "選別個体判定数:")?,
        シーン可視数: 値を読む(標準出力, "選別シーン可視数:")?,
        距離区分別の可視数: 添字付きの数を読む(標準出力, "選別距離区分別の可視数:")?,
        距離区分の和集合の可視数: 値を読む(標準出力, "選別距離区分の和集合の可視数:")?,
    })
}

fn パス別を読む(標準出力: &str, パス名: &str) -> Result<パス別描画発行, String> {
    Ok(パス別描画発行 {
        発行数: 値を読む(標準出力, &format!("{パス名}発行数:"))?,
        候補数: 値を読む(標準出力, &format!("{パス名}候補数:"))?,
        可視数: 値を読む(標準出力, &format!("{パス名}可視数:"))?,
        個体数: 値を読む(標準出力, &format!("{パス名}個体数:"))?,
        段別個体数: 添字付きの数を読む(標準出力, &format!("{パス名}段別個体数:"))?,
    })
}
