//! アプリの終了時報告から検収が使う数を取り出す工程。受け取るのは標準出力、返すのはパス別の描画発行と可視個体の選別の計数と確保数である。
//! 行の綴りは`crates/blitz_app/src/reports/draw_issue.rs`の出力と一致させている。
//! パスはシーンと距離区分0から距離区分3の5つであり、距離区分ごとに同じ5行の組が出る
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」)。
//! 行から値を取り出す工程は`line_read`、報告全体を1つの計数報告へ写す工程は`extract`にある。

mod extract;
mod line_read;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct パス別描画発行 {
    pub 発行数: u64,
    pub 候補数: u64,
    pub 可視数: u64,
    pub 個体数: u64,
    /// 段番号ごとの個体数。添字が段番号であり、報告の行に現れた段までを持つ。
    pub 段別個体数: Vec<u64>,
    /// このパスが積んだ発行のインデックス数とインスタンス数の積の総和。頂点処理量の代理変数である。
    pub 投入インデックス数: u64,
    /// 記録が`vkCmdDrawIndexed`を呼んだ回数。発行数と観測地点が違い、2つの一致が記録の整合の証拠になる。
    pub 描画数: u64,
    /// 記録が`vkCmdBindPipeline`を呼んだ回数。
    pub パイプライン切替: u64,
    /// 直前に描いた発行の材質から変わった回数。1件目も1回と数える。シャドウは材質を読まないため常に0である。
    pub 材質切替: u64,
}

/// 距離区分の数。レンダラーの`距離区分数`と同じ値であり、報告の行がこの数だけ並ぶ。
pub const 距離区分数: usize = 4;

/// 可視個体の選別がフレーム全体で数えた計数。レンダラー側の描画発行とは出どころが違い、2つの一致が整合の証拠になる。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 可視個体の選別の計数 {
    pub 候補数: u64,
    pub 個体判定数: u64,
    pub シーン可視数: u64,
    pub 距離区分別の可視数: Vec<u64>,
    /// 1つ以上の距離区分へ影を落とした個体の数。距離区分別の可視数の和と違い、複数の距離区分へ属する同じ個体を重複して数えない。
    pub 距離区分の和集合の可視数: u64,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 計数報告 {
    pub シーン: パス別描画発行,
    /// 距離区分0から距離区分3の描画発行。添字が距離区分番号である。
    pub 距離区分別のシャドウ: Vec<パス別描画発行>,
    pub 可視個体の選別: 可視個体の選別の計数,
    pub 現在確保数: u64,
    pub 最大同時確保数: u64,
    pub 段切替回数: u64,
    /// 可視判定と段選択へ登録されている群の件数。束の解除で材料と段の記憶が残っていないことをこの数で見る。
    pub 可視材料登録数: u64,
    pub 起動後シーン読込回数: u64,
    /// scene系のセット番号ごとにディスクリプタセットを束縛した回数。添字がセット番号(0=ビューとパス、1=ジオメトリ、2=材質、3=照明問い合わせ)である。
    pub セット別束縛回数: Vec<u64>,
    /// 公開中の資源表世代が積んだ材質の件数。
    pub 材質件数: u64,
    /// 公開中の資源表世代が常駐させたテクスチャの枚数。テクスチャを持たない材質だけのシーンでは正準フォールバックの3枚に収まる。
    pub 常駐画像枚数: u64,
    pub validation件数: u64,
}

/// シーンと距離区分0から距離区分3を名前付きで並べる。どのパスにも同じ条件を掛ける判定がこの走査を使う。
pub fn 全パスを並べる(計数: &計数報告) -> Vec<(String, &パス別描画発行)> {
    let mut 一覧 = vec![("シーンパス".to_string(), &計数.シーン)];
    for (番号, パス) in 計数.距離区分別のシャドウ.iter().enumerate() {
        一覧.push((format!("シャドウ距離区分{番号}"), パス));
    }
    一覧
}

