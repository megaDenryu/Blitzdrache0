//! ストリーミング要約の読み取りの検査。担当するのは、アプリが出す書式の標本から9つの数を採れることと、
//! 段が1つも無い実行の綴りを空の種類数として読めることを固定することである。

#![allow(clippy::unwrap_used)]

use super::*;
use crate::acceptance::検収の実行名;

const 標本の実行名: 検収の実行名 = 検収の実行名::定数から生成する("streaming_summary");

const 標本: &str = "ストリーミング要約:\n  観測フレーム数: 300\n  ディスク読込: 25件 / 11155300 bytes\n  GPU転送: 25件 / 11155300 bytes(見積)\n  GPU資源解除: 4件\n  上限: RAM 16777216 bytes / VRAM 16777216 bytes\n  最大使用量: RAM 8388608 bytes / VRAM 4194304 bytes\n  最大台帳登録数: 25\n  最終台帳登録数: 21\n  見送りフレーム数: 0\n  LOD変更フレーム数: 7\n  LOD変更時の読込開始: 0件\n  最終フレームの地形詳細段: 段0=3件 段1=2件\n";

const 段が無い標本: &str = "  最終フレームの地形詳細段: 常駐チャンクなし\n";

fn 報告にする(標準出力: &str) -> 終了時報告 {
    終了時報告::取り込む(&標本の実行名, 標準出力.to_string(), String::new())
}

#[test]
fn アプリの書式から9つの数を採る() {
    let 要約 = 取り出す(&報告にする(標本)).unwrap();
    assert_eq!(要約.ディスク読込件数, 25);
    assert_eq!(要約.ディスク読込バイト数, 11_155_300);
    assert_eq!(要約.gpu解除件数, 4);
    assert_eq!(要約.最大ramバイト数, 8_388_608);
    assert_eq!(要約.最大vramバイト数, 4_194_304);
    assert_eq!(要約.最大台帳登録数, 25);
    assert_eq!(要約.最終台帳登録数, 21);
    assert_eq!(要約.詳細段の変更フレーム数, 7);
    assert_eq!(要約.詳細段の変更時の読込開始件数, 0);
    assert_eq!(要約.最終段種類数, 2);
}

#[test]
fn 常駐チャンクが無い実行の段の種類数は零である() {
    let 差し替えた標本 = 標本.replace("  最終フレームの地形詳細段: 段0=3件 段1=2件\n", 段が無い標本);
    assert_eq!(取り出す(&報告にする(&差し替えた標本)).unwrap().最終段種類数, 0);
}

#[test]
fn 行が無ければ失敗にする() {
    assert!(取り出す(&報告にする("何もない出力\n")).is_err());
}
