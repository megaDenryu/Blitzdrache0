//! 構造の検証器の試験が共有する小さな設計関係グラフと、命題を組む補助。
//!
//! 判定そのものは子モジュールが持つ。グラフの組み立てをここへ置くのは、3つの未決定の試験と関係の試験が
//! 同じ1つのグラフを見ることがそれぞれの判定の前提だからである。

#![allow(clippy::unwrap_used)]

mod relation_tests;
mod undecided_tests;

use std::path::PathBuf;

use crate::design_model::{抽出の出どころ, 抽出元の構文, 設計概念, 設計概念の識別子, 設計関係, 設計関係の種類, 設計関係グラフ};

use super::super::atom::{原子命題, 項};
use super::super::proposition::命題;

fn 識別子(名前: &str) -> 設計概念の識別子 {
    設計概念の識別子::生成する("blitz_esca::traveler", 名前)
}

fn 関係(主語: &str, 種類: 設計関係の種類, 目的語: &str) -> 設計関係 {
    設計関係 {
        主語: 識別子(主語),
        種類,
        目的語: 識別子(目的語),
        出どころ: 抽出の出どころ {
            パス: PathBuf::from("crates/blitz_esca/src/traveler.rs"),
            行番号: 1,
            構文: 抽出元の構文::構造体のフィールド,
        },
    }
}

/// 旅行者が旅行者IDを保持し、旅行者IDが旅行者を識別するグラフ。関係へ参加しない概念も1件持つ。
fn 小さなグラフ() -> 設計関係グラフ {
    設計関係グラフ::生成する(
        vec![
            設計概念::型として生成する("blitz_esca::traveler", "旅行者"),
            設計概念::型として生成する("blitz_esca::traveler", "旅行者ID"),
            設計概念::型として生成する("blitz_esca::traveler", "関係へ参加しない型"),
        ],
        vec![関係("旅行者", 設計関係の種類::保持する, "旅行者ID"), 関係("旅行者ID", 設計関係の種類::識別する, "旅行者")],
    )
}

fn 関係の原子(主語: &str, 種類: 設計関係の種類, 目的語: &str) -> 命題 {
    命題::原子から組む(原子命題::設計関係が在る {
        主語: 項::名指した概念(識別子(主語)),
        種類,
        目的語: 項::名指した概念(識別子(目的語)),
    })
}
