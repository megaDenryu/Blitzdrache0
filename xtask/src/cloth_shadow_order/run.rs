//! 検収1条件ぶんの起動の指定。受け取るのは条件と監視先のエントリファイル、返すのは実行環境へ渡す起動指定である。
//! 起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! quadシーンを`--object-count 2`で描くと、同じ板が別々の配置変換で左右に2つ並ぶ。並びが左右に離れているため、
//! 走査順を入れ替えても幾何は1画素も変わらない。板が重なる構図を選ぶと、同一平面の奥行き競合が走査順で決着を変え、
//! 布とは無関係な差が出てしまう。
//!
//! 布は板の手前に垂れ、方向光が板の上へ布の影を落とす。この影が走査順で動かないことがこの検収の対象である。
//! ポスト処理を外すのは、光のにじみが布シミュレーションのわずかな揺れを画面全体へ広げるためである。
//! フレーム数を3に取るのは、布の自己衝突がGPUの原子的加算の順序に依存し、歩進を重ねるほど実行ごとの差が育つためである。
//! 実測では3歩進までは同一条件2回の読み戻しがバイト一致し、4歩進から差が出はじめる。布は初期形状のまま垂れており、影は最初の歩進から板に出る。

use std::path::{Path, PathBuf};

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収エラー, 検収シーン名
};

const アセットルート: &str = "target/runtime_assets";
const シーン名: 検収シーン名 = 検収シーン名::生成する("quad");
const 描画対象数: &str = "2";
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(3);

#[derive(Clone, Copy)]
pub(super) enum 条件 {
    布あり読込順, // シーンデータの並び順に描画対象を載せる。比べる基準になる条件
    布あり逆順,   // 描画対象の並びだけを逆にする。読込順との差が走査順への依存になる
    布なし読込順, // 読込順のまま布だけを外す。読込順の布影領域を切り出す下敷き
    布なし逆順,   // 逆順のまま布だけを外す。逆順の布影領域を切り出す下敷き
}

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::綴りから生成する(アセットルート),
        出力ディレクトリ,
    )
}

pub(super) fn 起動指定を組み立てる(条件: 条件, シェーダー入口: &Path) -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数)
        .値を持つ選択肢を足す("--object-count", 描画対象数)
        .選択肢を足す("--no-post")
        .選択肢をまとめて足す(条件別の選択肢(条件))
        .パスを値に持つ選択肢を足す("--shader-source", シェーダー入口)
}

fn 条件別の選択肢(条件: 条件) -> &'static [&'static str] {
    match 条件 {
        条件::布あり読込順 => &["--cloth"],
        条件::布あり逆順 => &["--cloth", "--reverse-draw-order"],
        条件::布なし読込順 => &[],
        条件::布なし逆順 => &["--reverse-draw-order"],
    }
}
