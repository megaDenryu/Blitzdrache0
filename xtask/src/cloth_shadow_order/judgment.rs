//! 布の影が覆う画素の集合を切り出し、2つの集合を比べる工程。受け取るのは実行結果の対、返すのは領域と画素数である。
//!
//! 布の影だけを取り出せるのは、この構図の受け手(2枚の板)が布と別の色で塗られているからである。布を足したときに
//! 暗くなり、かつ布そのものの色になっていない画素が、布の影で暗くなった受け手である。
//!
//! 生の画像同士を比べないのは、布の自己衝突がGPUの原子的加算の順序に依存し、布そのものの画素が実行ごとに
//! 最下位ビットだけ揺れるためである。影の領域は輝度のしきい値で切るため、この揺れを拾わない。

use std::collections::HashSet;

use crate::acceptance::読み戻し画像;

/// 布の色(0.55, 0.1, 0.12)を受け手の色と分ける差。受け手の板は緑一色のため、この差で2つは確実に分かれる。
const 赤の突出しきい値: u16 = 20;
/// 影が覆ったと認める輝度の下がり幅(RGB3成分の合計)。布の影は受け手を大きく暗くするため、この値は境界のにじみだけを落とす。
const 影と認める輝度差: u16 = 24;

pub(super) struct 布影領域 {
    画素位置一覧: HashSet<usize>,
}

impl 布影領域 {
    pub(super) fn 画素数(&self) -> usize {
        self.画素位置一覧.len()
    }

    /// 片方にしか無い画素の数。位置がずれた影はここに大きな値として現れる。
    pub(super) fn 差の画素数(&self, 他: &Self) -> usize {
        self.画素位置一覧.symmetric_difference(&他.画素位置一覧).count()
    }
}

pub(super) fn 布影領域を求める(布あり: &読み戻し画像, 布なし: &読み戻し画像) -> Result<布影領域, String> {
    寸法が同じことを確かめる(布あり, 布なし)?;
    let mut 画素位置一覧 = HashSet::new();
    for (位置, (左, 右)) in 布あり.画素列().zip(布なし.画素列()).enumerate() {
        if 赤が突出しているか(左) {
            continue;
        }
        if 輝度(右).saturating_sub(輝度(左)) >= 影と認める輝度差 {
            画素位置一覧.insert(位置);
        }
    }
    Ok(布影領域 { 画素位置一覧 })
}

fn 赤が突出しているか(画素: &[u8]) -> bool {
    let (赤, 緑, 青) = (u16::from(画素[0]), u16::from(画素[1]), u16::from(画素[2]));
    赤 > 緑 + 赤の突出しきい値 && 赤 > 青 + 赤の突出しきい値
}

fn 輝度(画素: &[u8]) -> u16 {
    u16::from(画素[0]) + u16::from(画素[1]) + u16::from(画素[2])
}

fn 寸法が同じことを確かめる(左画像: &読み戻し画像, 右画像: &読み戻し画像) -> Result<(), String> {
    let (左幅, 左高さ) = (左画像.幅().画素数(), 左画像.高さ().画素数());
    let (右幅, 右高さ) = (右画像.幅().画素数(), 右画像.高さ().画素数());
    if (左幅, 左高さ) != (右幅, 右高さ) {
        return Err(format!("2実行の読み戻し寸法が違う: {左幅}x{左高さ}と{右幅}x{右高さ}"));
    }
    Ok(())
}
