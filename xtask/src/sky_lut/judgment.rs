//! 生成パス数の期待値と、両条件が共有する列の見方。
//! 本数は指示の4値と1対1に対応する。前の結果を使うが0本、空中遠近だけ焼き直すが1本、スカイビューと空中遠近を
//! 焼き直すが2本、全部焼き直すが4本である。
//!
//! 条件ごとの判定を別のモジュールへ置くのは、2つが互いの負の対照であり期待そのものが違うためである。
//! 時計停止の判定は「常に4本」を、時計進行の判定は「常に0本」を落とす。1本のフレームはカメラだけが
//! 動いたときに現れるが、blitz_appにフレーム間でカメラを動かす起動指定が無いため2条件はどちらも1本を観測しない
//! (1本の列に対する判定の答えは各条件の単体テストが固定する)。

mod clock_advancing;
mod clock_stopped;

pub(super) use clock_advancing::時計進行を判定する;
pub(super) use clock_stopped::時計停止を判定する;

use super::pass_count::生成パス数の列;

/// 4枚すべてを焼く本数(透過率・多重散乱・スカイビュー・空中遠近)。
const 全部の本数: u32 = 4;
/// 太陽が動いたフレームが焼く本数。スカイビューと、それに続く空中遠近の2本である。
const 太陽が動いた本数: u32 = 2;

/// まだ1枚も焼いていない初回フレームは、条件に依らず4枚すべてを焼く。
fn 初回が全部であることを確かめる(列: &生成パス数の列, 条件名: &str) -> Result<(), String> {
    let 先頭 = 列.フレームごと.first().copied().unwrap_or(0);
    if 先頭 != 全部の本数 {
        return Err(format!("{条件名}の初回フレームは{全部の本数}本を焼くべきだが{先頭}本だった"));
    }
    Ok(())
}

/// 初回を除いた並び。初回だけが「まだ1枚も焼いていない」ことに由来する別の期待を持つ。
fn 二フレーム目以降(列: &生成パス数の列) -> impl Iterator<Item = (usize, u32)> + '_ {
    列.フレームごと.iter().copied().enumerate().skip(1)
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
pub(super) mod test_series {
    use super::生成パス数の列;

    /// 本数の並びだけを見る判定の検査に使う列。列の長さと総数は整合した値を置く。
    /// 長さそのものの整合は`series_integrity`が受け持つ。
    /// 停止点の判定の検査も同じ列を使うため、可視性をsky_lut全体へ広げてある。
    pub(in crate::sky_lut) fn 列を作る(フレームごと: Vec<u32>) -> 生成パス数の列 {
        let 長さ = u64::try_from(フレームごと.len()).unwrap();
        生成パス数の列 {
            数えたフレーム数: 長さ,
            総数: フレームごと.iter().map(|値| u64::from(*値)).sum(),
            報告された列の長さ: 長さ,
            フレームごと,
        }
    }
}
