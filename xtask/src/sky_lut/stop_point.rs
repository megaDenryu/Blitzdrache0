use crate::acceptance::{判定の名前, 判定の破れ, 検収エラー, 終了時報告};

/// 合成を切った実行に現れてはならない区間。どちらもこの段で足したパスの名前である。
const 現れてはならない区間: [&str; 2] = ["空中遠近合成", "空中遠近生成"];
/// 合成を切った初回フレームが焼く本数。透過率・多重散乱・スカイビューの3枚であり、空中遠近は焼かない。
const 合成なしの初回の本数: u32 = 3;

const 合成なしの初回フレームの本数: 判定の名前 = 判定の名前::定数から生成する("合成なしの初回フレームが焼いた本数");
const 二条件の読み戻しのバイト長: 判定の名前 = 判定の名前::定数から生成する("合成なしと合成ありの読み戻しのバイト長");
const 合成ありとの差分バイト: 判定の名前 =
    判定の名前::定数から生成する("合成ありと合成なしの絵の差分バイト(1つも無ければ合成が絵を1画素も変えていない)");

pub(super) fn 停止点を判定する(
    合成なしの報告: &終了時報告,
    合成なしの列: &生成パス数の列,
    合成なしの画素: &[u8],
    合成ありの画素: &[u8],
) -> Result<String, 検収エラー> {
    gpu_time::区間が無いことを確かめる(合成なしの報告, &現れてはならない区間)?;
    列を判定する(合成なしの列)?;
    let 差分バイト数 = 差分を数える(合成なしの画素, 合成ありの画素)?;
    if 差分バイト数 == 0 {
        return Err(合成ありとの差分バイト.あるはずのものが無い破れ().into());
    }
    Ok(format!(
        "合成なしは初回{}本のみで空中遠近を焼かず、合成の2区間がどちらも立たず、合成ありとの差分は{差分バイト数}バイト",
        合成なしの列.総数
    ))
}

/// 初回が3本、以降が0本であることを見る。空中遠近を焼かないことがこの並びに現れる。
fn 列を判定する(列: &生成パス数の列) -> Result<(), 判定の破れ> {
    let 先頭 = 列.フレームごと.first().copied().unwrap_or(0);
    合成なしの初回フレームの本数.一致を課す(先頭, 合成なしの初回の本数)?;
    for (添字, 本数) in 列.フレームごと.iter().copied().enumerate().skip(1) {
        フレームが焼いた本数の判定名(添字).零件であることを課す(本数)?;
    }
    Ok(())
}

fn フレームが焼いた本数の判定名(フレーム番号: usize) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("合成なしの{フレーム番号}フレーム目が焼いた本数"))
}

fn 差分を数える(左: &[u8], 右: &[u8]) -> Result<usize, 判定の破れ> {
    二条件の読み戻しのバイト長.一致を課す(左.len(), 右.len())?;
    Ok(左.iter().zip(右.iter()).filter(|(左値, 右値)| 左値 != 右値).count())
}
