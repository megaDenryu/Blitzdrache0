//! 合成を切った条件が停止点として成立していることの判定。担当する工程は「合成なしの実行と合成ありの実行を
//! 受け取り、合成の経路が1本も走っていないこと・絵が合成ありと違うことを確かめる」ことである。
//! 返すのは判定が見た数を並べた文である。
//!
//! 停止点が意味するのは、起動指定1つで空中遠近を入れる前の描画へ戻れることである。それを機械で見るのに
//! 保存した基準画像との一致を使わない。読み戻しの画素は機材と実装で変わりうるため、リポジトリへ焼いた
//! 期待画像やそのハッシュは別の機材で必ず落ちる。代わりに「合成の経路が1つも走っていない」ことを走った
//! パスそのもので確かめる。合成のパスも空中遠近の生成パスもグラフへ積まれていなければ、残る描画は
//! 合成を入れる前と同じ経路であり、絵も同じである。
//!
//! 合成ありとの不一致を併せて見るのは負の対照である。これが無いと、合成が絵を1画素も変えていない実装でも
//! 停止点の判定が通る。

use super::gpu_time;
use super::pass_count::生成パス数の列;

/// 合成を切った実行に現れてはならない区間。どちらもこの段で足したパスの名前である。
const 現れてはならない区間: [&str; 2] = ["空中遠近合成", "空中遠近生成"];
/// 合成を切った初回フレームが焼く本数。透過率・多重散乱・スカイビューの3枚であり、空中遠近は焼かない。
const 合成なしの初回の本数: u32 = 3;

pub(super) fn 停止点を判定する(
    合成なしの出力: &str,
    合成なしの列: &生成パス数の列,
    合成なしの画素: &[u8],
    合成ありの画素: &[u8],
) -> Result<String, String> {
    gpu_time::区間が無いことを確かめる(合成なしの出力, &現れてはならない区間)?;
    列を判定する(合成なしの列)?;
    let 差分バイト数 = 差分を数える(合成なしの画素, 合成ありの画素)?;
    if 差分バイト数 == 0 {
        return Err("合成ありと合成なしの絵がバイト一致した(合成が絵を1画素も変えていない)".to_string());
    }
    Ok(format!(
        "合成なしは初回{}本のみで空中遠近を焼かず、合成の2区間がどちらも立たず、合成ありとの差分は{差分バイト数}バイト",
        合成なしの列.総数
    ))
}

/// 初回が3本、以降が0本であることを見る。空中遠近を焼かないことがこの並びに現れる。
fn 列を判定する(列: &生成パス数の列) -> Result<(), String> {
    let 先頭 = 列.フレームごと.first().copied().unwrap_or(0);
    if 先頭 != 合成なしの初回の本数 {
        return Err(format!("合成なしの初回フレームは{合成なしの初回の本数}本を焼くべきだが{先頭}本だった"));
    }
    for (添字, 本数) in 列.フレームごと.iter().copied().enumerate().skip(1) {
        if 本数 != 0 {
            return Err(format!("合成なしの{添字}フレーム目が0本でなく{本数}本を焼いた"));
        }
    }
    Ok(())
}

fn 差分を数える(左: &[u8], 右: &[u8]) -> Result<usize, String> {
    if 左.len() != 右.len() {
        return Err(format!("2条件の読み戻しのバイト長が違う: {} と {}", 左.len(), 右.len()));
    }
    Ok(左.iter().zip(右.iter()).filter(|(左値, 右値)| 左値 != 右値).count())
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::super::judgment::test_series::列を作る;
    use super::*;

    const 合成なしの標本: &str = "パス別GPU時間(移動平均、60フレーム窓):\n  透過率生成: 0.1000 ms\n  スカイビュー生成: 0.3000 ms\n  空: 0.0154 ms\n";
    const 合成ありの標本: &str = "パス別GPU時間(移動平均、60フレーム窓):\n  空中遠近生成: 0.4000 ms\n  空中遠近合成: 0.0500 ms\n  空: 0.0154 ms\n";

    #[test]
    fn 合成の経路が走らず絵が違えば合格にする() {
        let 判定 = 停止点を判定する(合成なしの標本, &列を作る(vec![3, 0, 0]), &[1, 2, 3], &[1, 2, 4]);
        assert!(判定.is_ok(), "{判定:?}");
    }

    /// 負の対照: 合成の区間が立っていたら停止点として通さない。
    #[test]
    fn 合成の区間が立ったら落とす() {
        assert!(停止点を判定する(合成ありの標本, &列を作る(vec![3, 0, 0]), &[1, 2, 3], &[1, 2, 4]).is_err());
    }

    /// 負の対照: 絵が一致したら、合成が何もしていない実装を見逃さないため落とす。
    #[test]
    fn 絵が一致したら落とす() {
        assert!(停止点を判定する(合成なしの標本, &列を作る(vec![3, 0, 0]), &[1, 2, 3], &[1, 2, 3]).is_err());
    }

    /// 負の対照: 空中遠近を焼くフレームが混じったら落とす。
    #[test]
    fn 焼き直しが混じったら落とす() {
        assert!(停止点を判定する(合成なしの標本, &列を作る(vec![3, 1, 0]), &[1, 2, 3], &[1, 2, 4]).is_err());
    }
}
