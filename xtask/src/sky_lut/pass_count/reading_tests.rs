//! 生成パス数の行の読み取りの検査。担当するのは、報告の行から列と3つの数を読めることと、
//! 行が無い出力を落とすことを標本で固定することである。

#![allow(clippy::unwrap_used)]

use super::*;
use crate::acceptance::検収の実行名;

const 標本の実行名: 検収の実行名 = 検収の実行名::定数から生成する("sky_lut_pass_count");
const 標本: &str = "大気のベイク済み画像生成パス数 数えたフレーム数=4 総数=3 列の長さ=4 列=3,0,0,0\n";

fn 報告にする(標準出力: &str) -> 終了時報告 {
    終了時報告::取り込む(&標本の実行名, 標準出力.to_string(), String::new())
}

#[test]
fn 報告行から列を読む() {
    let 列 = 読む(&報告にする(標本), "標本").unwrap();
    assert_eq!(列.数えたフレーム数, 4);
    assert_eq!(列.総数, 3);
    assert_eq!(列.報告された列の長さ, 4);
    assert_eq!(列.フレームごと, vec![3, 0, 0, 0]);
    assert_eq!(列.本数の回数(0), 3);
}

#[test]
fn 行が無ければ失敗にする() {
    assert!(読む(&報告にする("何もない出力\n"), "標本").is_err());
}
