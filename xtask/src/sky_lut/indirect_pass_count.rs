//! 間接照明の表現の生成パス数を判定する工程。受け取るのは3条件の標準出力、返すのは報告へ載せる要約である。
//!
//! 地形の本番世界が天空の遠方環境を選ぶようになったため、判定は「1本も焼いていない」から「更新計画どおりの
//! 本数を焼いた」へ変わった(参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Ic-3bの実装」)。
//!
//! 1フレームぶんの本数をここで組み立てないのは、本番のレンダーグラフが誤った本数を積んでもこの判定が通って
//! しまうためである。本数は同じ実行が出す見込みの行(本番の`焼き上げの計画::本数`が答えた値)から読み、この工程が
//! 決めるのは条件ごとに何フレームが焼くかだけである。
//!
//! 時計を止めた条件と合成なしの条件は遠方環境キーが動かないため初回の1フレームだけが焼く。時計を進める条件は
//! スカイビューキーの変化が遠方環境キーへ波及するため全フレームが焼く。この2つは互いの負の対照であり、
//! 片方だけでは「常に焼く」「初回しか焼かない」のどちらの誤りも見分けられない。

pub(crate) mod rows;
#[cfg(test)]
mod tests;

use rows::{実測, 見込み};

/// その条件で遠方環境を焼くフレームの取り方。
#[derive(Clone, Copy)]
enum 焼き方 {
    /// 遠方環境キーが1度も変わらないため、まだ焼いていない初回のフレームだけが焼く。
    初回だけ,
    /// 毎フレーム遠方環境キーが変わるため、数えたすべてのフレームが焼く。
    毎フレーム,
}

/// 3条件の実測が更新計画どおりであることを確かめ、報告へ載せる要約を返す。
pub(super) fn 三条件を確かめる(停止: &str, 進行: &str, 合成なし: &str) -> Result<String, String> {
    let 見込み = rows::見込みを読む(停止, "時計停止")?;
    見込みが揃うことを確かめる(見込み, 進行, "時計進行")?;
    見込みが揃うことを確かめる(見込み, 合成なし, "合成なし")?;
    let 停止の実測 = 条件を確かめる(停止, "時計停止", 焼き方::初回だけ, 見込み)?;
    let 進行の実測 = 条件を確かめる(進行, "時計進行", 焼き方::毎フレーム, 見込み)?;
    条件を確かめる(合成なし, "合成なし", 焼き方::初回だけ, 見込み)?;
    Ok(format!(
        "初回{}本・焼き直し{}本の計画で、時計停止と合成なしは{}フレーム中1フレームが焼いて総数{}本、時計進行は{}フレームすべてが焼いて総数{}本",
        見込み.初回の合計, 見込み.焼き直しの合計, 停止の実測.数えたフレーム数, 停止の実測.総数, 進行の実測.数えたフレーム数, 進行の実測.総数
    ))
}

/// 見込みは同じ資源構成から導かれるため3条件で一致する。食い違ったら条件ごとに別の粗さ段数が立っている。
fn 見込みが揃うことを確かめる(基準: 見込み, 標準出力: &str, 条件名: &str) -> Result<(), String> {
    let 読んだ = rows::見込みを読む(標準出力, 条件名)?;
    if 読んだ != 基準 {
        return Err(format!("{条件名}の見込み{読んだ:?}が時計停止の見込み{基準:?}と違う"));
    }
    Ok(())
}

fn 条件を確かめる(標準出力: &str, 条件名: &str, 焼き方: 焼き方, 見込み: 見込み) -> Result<実測, String> {
    let 実測 = rows::実測を読む(標準出力, 条件名)?;
    // 1フレームも数えていない実行は、初回のフレームが焼いたかどうかを判定できない。総数0を素通しにしない。
    if 実測.数えたフレーム数 == 0 {
        return Err(format!("{条件名}の間接照明が1フレームも数えていない"));
    }
    let 焼くフレーム数 = match 焼き方 {
        焼き方::初回だけ => 1,
        焼き方::毎フレーム => 実測.数えたフレーム数,
    };
    if 実測.焼き直したフレーム数 != 焼くフレーム数 {
        return Err(format!(
            "{条件名}の焼き直したフレーム数が{}で、期待{焼くフレーム数}と違う",
            実測.焼き直したフレーム数
        ));
    }
    let 期待の総数 = 見込み.初回の合計 + 見込み.焼き直しの合計 * (焼くフレーム数 - 1);
    if 実測.総数 != 期待の総数 {
        return Err(format!("{条件名}の総数が{}で、期待{期待の総数}と違う", 実測.総数));
    }
    Ok(実測)
}
