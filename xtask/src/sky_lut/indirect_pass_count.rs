//! 間接照明の表現の生成パス数を判定する工程。受け取るのは3条件の標準出力、返すのは報告へ載せる要約である。
//!
//! 地形の本番世界が天空の遠方環境を選ぶようになったため、判定は「1本も焼いていない」から「更新計画どおりの
//! 本数を焼いた」へ変わった(参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Ic-3bの実装」)。
//!
//! 1フレームぶんの本数をここで組み立てないのは、本番のレンダーグラフが誤った本数を積んでもこの判定が通って
//! しまうためである。本数は同じ実行が出す見込みの行(本番の`焼き上げの計画::本数`が答えた値)から読み、この工程が
//! 決めるのは条件ごとに何フレームが焼くかだけである。
//!
//! 焼くフレーム数を「太陽天頂区間が変わった回数+初回の1回」で立てるのは、間引きが入って以降、時計を進めても
//! 区間の中のフレームは焼かないためである。回数は本番の記録が出す整数をそのまま読み、検収側で数え直さない。
//! 時計を止めた条件と合成なしの条件は区間が1度も変わらず、時計を進める条件は跨ぐたびに焼く。この2つは互いの
//! 負の対照であり、片方だけでは「常に焼く」「初回しか焼かない」のどちらの誤りも見分けられない。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」

pub(crate) mod rows;
#[cfg(test)]
mod tests;

use rows::{実測, 見込み};

/// その条件で遠方環境を焼くフレームの取り方。どちらも焼くフレーム数は「区間が変わった回数+1」であり、
/// 違うのは区間が変わること自体をその条件が要求するかどうかである。
#[derive(Clone, Copy)]
pub(crate) enum 焼き方 {
    /// 太陽が動かないため区間が1度も変わらず、まだ焼いていない初回のフレームだけが焼く。
    初回だけ,
    /// 太陽が動いて区間を跨ぐたびに焼く。1度も跨がない実行はこの条件が成立していない。
    区間が変わるたび,
}

/// 3条件の実測が更新計画どおりであることを確かめ、報告へ載せる要約を返す。
pub(super) fn 三条件を確かめる(停止: &str, 進行: &str, 合成なし: &str) -> Result<String, String> {
    let 見込み = rows::見込みを読む(停止, "時計停止")?;
    見込みが揃うことを確かめる(見込み, 進行, "時計進行")?;
    見込みが揃うことを確かめる(見込み, 合成なし, "合成なし")?;
    let (停止の実測, _) = 条件を確かめる(停止, "時計停止", 焼き方::初回だけ, 見込み)?;
    let (進行の実測, 進行の変化回数) = 条件を確かめる(進行, "時計進行", 焼き方::区間が変わるたび, 見込み)?;
    条件を確かめる(合成なし, "合成なし", 焼き方::初回だけ, 見込み)?;
    Ok(format!(
        "初回{}本・焼き直し{}本の計画で、時計停止と合成なしは{}フレーム中1フレームが焼いて総数{}本、時計進行は太陽天頂区間が{進行の変化回数}回変わり{}フレームが焼いて総数{}本",
        見込み.初回の合計, 見込み.焼き直しの合計, 停止の実測.数えたフレーム数, 停止の実測.総数, 進行の実測.焼き直したフレーム数, 進行の実測.総数
    ))
}

/// 見込みは同じ資源構成から導かれるため3条件で一致する。食い違ったら条件ごとに別の粗さ段数が立っている。
fn 見込みが揃うことを確かめる(基準: 見込み, 標準出力: &str, 条件名: &str) -> Result<(), String> {
    let 読んだ = rows::見込みを読む(標準出力, 条件名)?;
    if 読んだ != 基準 {
        return Err(format!("{条件名}の見込み{読んだ:?}が時計停止の見込み{基準:?}と違う"));
    }
    Ok(())
}

/// 実測と一緒に区間の変化回数も返すのは、要約の1文がその整数を載せるためである。同じ行を2度読まない。
fn 条件を確かめる(標準出力: &str, 条件名: &str, 焼き方: 焼き方, 見込み: 見込み) -> Result<(実測, u64), String> {
    let 実測 = rows::実測を読む(標準出力, 条件名)?;
    let 区間の変化回数 = rows::区間の変化回数を読む(標準出力, 条件名)?;
    本数を確かめる(実測, 見込み, 条件名, 焼き方, 区間の変化回数)?;
    Ok((実測, 区間の変化回数))
}

/// 読み取り済みの実測と見込みが更新計画どおりであることを確かめる。
/// 読み取りと分けてあるのは、行を先に読んでおきたい呼び出し元(`indirect-cost`)が同じ期待の組み立てを二重に持たずに済むようにするためである。
pub(crate) fn 本数を確かめる(
    実測: 実測, 見込み: 見込み, 条件名: &str, 焼き方: 焼き方, 区間の変化回数: u64
) -> Result<(), String> {
    // 1フレームも数えていない実行は、初回のフレームが焼いたかどうかを判定できない。総数0を素通しにしない。
    if 実測.数えたフレーム数 == 0 {
        return Err(format!("{条件名}の間接照明が1フレームも数えていない"));
    }
    区間の変化を確かめる(条件名, 焼き方, 区間の変化回数)?;
    let 焼くフレーム数 = 区間の変化回数 + 1;
    if 実測.焼き直したフレーム数 != 焼くフレーム数 {
        return Err(format!(
            "{条件名}の焼き直したフレーム数が{}で、区間の変化{区間の変化回数}回から立てた期待{焼くフレーム数}と違う",
            実測.焼き直したフレーム数
        ));
    }
    let 期待の総数 = 見込み.初回の合計 + 見込み.焼き直しの合計 * (焼くフレーム数 - 1);
    if 実測.総数 != 期待の総数 {
        return Err(format!("{条件名}の総数が{}で、期待{期待の総数}と違う", 実測.総数));
    }
    Ok(())
}

/// その条件が要求する区間の動き方。時計を止めた条件で区間が動くのは時刻が進んでいることを、時計を進めた条件で
/// 1度も動かないのは太陽が動いていないか刻みが粗すぎることを意味し、どちらも測るべき状態を測っていない。
fn 区間の変化を確かめる(条件名: &str, 焼き方: 焼き方, 区間の変化回数: u64) -> Result<(), String> {
    match 焼き方 {
        焼き方::初回だけ if 区間の変化回数 != 0 => {
            Err(format!("{条件名}は太陽が動かない条件なのに太陽天頂区間が{区間の変化回数}回変わった"))
        }
        焼き方::区間が変わるたび if 区間の変化回数 == 0 => {
            Err(format!("{条件名}は太陽が動く条件なのに太陽天頂区間が1度も変わっていない"))
        }
        _ => Ok(()),
    }
}
