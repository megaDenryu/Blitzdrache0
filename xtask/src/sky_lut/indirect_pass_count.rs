//! 間接照明の表現の生成パス数を判定する工程。受け取るのは3条件の終了時報告、返すのは報告へ載せる要約である。
//!
//! 地形の本番世界が天空の遠方環境を選ぶようになったため、判定は「1本も焼いていない」から「更新計画どおりの
//! 本数を焼いた」へ変わった(参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Ic-3bの実装」)。
//!
//! 1フレームぶんの本数をここで組み立てないのは、本番のレンダーグラフが誤った本数を積んでもこの判定が通って
//! しまうためである。本数は同じ実行が出す見込みの行(本番の`焼き上げの計画::本数`が答えた値)から読み、この工程が
//! 決めるのは条件ごとに何フレームが焼くかだけである。
//!
//! 焼くフレーム数を「太陽天頂区間が変わった回数+初回の1回」で立てるのは、間引きが入って以降、時計を進めても
//! 区間の中のフレームは焼かないためである。回数は本番の記録が出す整数をそのまま読み、検収側で数え直さない。
//! 時計を止めた条件と合成なしの条件は区間が1度も変わらず、時計を進める条件は跨ぐたびに焼く。この2つは互いの
//! 負の対照であり、片方だけでは「常に焼く」「初回しか焼かない」のどちらの誤りも見分けられない。
//! 1条件ぶんの本数の判定そのものは`count_judgment`が持つ。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「間引きの実装設計」

mod count_judgment;
pub(crate) mod rows;
#[cfg(test)]
mod tests;

pub(crate) use count_judgment::本数を確かめる;

use rows::{実測, 見込み};

use crate::acceptance::{判定の名前, 検収エラー, 終了時報告};

/// その条件で遠方環境を焼くフレームの取り方。どちらも焼くフレーム数は「区間が変わった回数+1」であり、
/// 違うのは区間が変わること自体をその条件が要求するかどうかである。
#[derive(Clone, Copy)]
pub(crate) enum 焼き方 {
    初回だけ,         // 太陽が動かないため区間が1度も変わらず、まだ焼いていない初回のフレームだけが焼く
    区間が変わるたび, // 太陽が動いて区間を跨ぐたびに焼く。1度も跨がない実行はこの条件が成立していない
}

/// 3条件の実測が更新計画どおりであることを確かめ、報告へ載せる要約を返す。
pub(super) fn 三条件を確かめる(
    停止: &終了時報告, 進行: &終了時報告, 合成なし: &終了時報告
) -> Result<String, 検収エラー> {
    let 見込み = rows::見込みを読む(停止, "時計停止")?;
    見込みが揃うことを確かめる(見込み, 進行, "時計進行")?;
    見込みが揃うことを確かめる(見込み, 合成なし, "合成なし")?;
    let (停止の実測, _) = 条件を確かめる(停止, "時計停止", 焼き方::初回だけ, 見込み)?;
    let (進行の実測, 進行の変化回数) = 条件を確かめる(進行, "時計進行", 焼き方::区間が変わるたび, 見込み)?;
    条件を確かめる(合成なし, "合成なし", 焼き方::初回だけ, 見込み)?;
    Ok(format!(
        "初回{}本・焼き直し{}本の計画で、時計停止と合成なしは{}フレーム中1フレームが焼いて総数{}本、時計進行は太陽天頂区間が{進行の変化回数}回変わり{}フレームが焼いて総数{}本",
        見込み.初回の合計, 見込み.焼き直しの合計, 停止の実測.数えたフレーム数, 停止の実測.総数, 進行の実測.焼き直したフレーム数, 進行の実測.総数
    ))
}

/// 見込みは同じ資源構成から導かれるため3条件で一致する。食い違ったら条件ごとに別の粗さ段数が立っている。
fn 見込みが揃うことを確かめる(基準: 見込み, 報告: &終了時報告, 条件名: &str) -> Result<(), 検収エラー> {
    let 読んだ = rows::見込みを読む(報告, 条件名)?;
    Ok(見込みの判定名(条件名).綴りの一致を課す(&format!("{読んだ:?}"), &format!("{基準:?}"))?)
}

/// 実測と一緒に区間の変化回数も返すのは、要約の1文がその整数を載せるためである。同じ行を2度読まない。
fn 条件を確かめる(
    報告: &終了時報告, 条件名: &str, 焼き方: 焼き方, 見込み: 見込み
) -> Result<(実測, u64), 検収エラー> {
    let 実測 = rows::実測を読む(報告)?;
    let 区間の変化回数 = rows::区間の変化回数を読む(報告)?;
    本数を確かめる(実測, 見込み, 条件名, 焼き方, 区間の変化回数)?;
    Ok((実測, 区間の変化回数))
}

fn 見込みの判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{条件名}の見込み(時計停止の見込みと食い違うなら条件ごとに別の粗さ段数が立っている)"
    ))
}
