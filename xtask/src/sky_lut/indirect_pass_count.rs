//! 間接照明の表現の生成パス数の報告行を読み、1本も焼いていないことを確かめる工程。
//! 受け取るのは標準出力と条件の名前、返すのは判定の結果である。
//! 行の綴りは`crates/blitz_app/src/reports/atmosphere_passes.rs`の出力と一致させている。
//!
//! 大気の本数と別の計数を読むのは、既存の判定値の意味を変えないためである。地形世界を含む全既存世界の
//! 間接照明方針は定数近似であり、遠方環境の照明資源そのものが作られない。したがって焼き直したフレーム数も
//! 総数も0でなければならず、0でなければ「絵が変わらない」というこの段の前提が破れている
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」)。

const 見出し: &str = "間接照明生成パス数";

/// 3条件とも1本も積んでいないことを確かめ、数えたフレーム数を返す。3条件を1つの呼び出しにするのは、
/// 期待がどれも同じ「0本」であり、条件ごとに書き分ける判断が1つも無いためである。
pub(super) fn 三条件を確かめる(停止: &str, 進行: &str, 合成なし: &str) -> Result<u64, String> {
    let フレーム数 = 焼いていないことを確かめる(停止, "時計停止")?;
    焼いていないことを確かめる(進行, "時計進行")?;
    焼いていないことを確かめる(合成なし, "合成なし")?;
    Ok(フレーム数)
}

/// 定数近似の契約で1本も積んでいないことを確かめる。数えたフレーム数だけを返し、報告の文面へ載せる。
fn 焼いていないことを確かめる(標準出力: &str, 条件名: &str) -> Result<u64, String> {
    let 行 = 標準出力
        .lines()
        .find(|行| 行.starts_with(見出し))
        .ok_or_else(|| format!("{条件名}の出力に{見出し}の行が無い"))?;
    let 数えたフレーム数 = 数を読む(行, "数えたフレーム数=", 条件名)?;
    for 前置き in ["焼き直したフレーム数=", "総数="] {
        let 値 = 数を読む(行, 前置き, 条件名)?;
        if 値 != 0 {
            return Err(format!("{条件名}の{見出し}の{前置き}は定数近似の契約では0であるべきだが{値}だった"));
        }
    }
    Ok(数えたフレーム数)
}

fn 数を読む(行: &str, 前置き: &str, 条件名: &str) -> Result<u64, String> {
    let 残り = 行
        .split(前置き)
        .nth(1)
        .ok_or_else(|| format!("{条件名}の{見出し}の行に{前置き}が無い: {行}"))?;
    let 語 = 残り.split_whitespace().next().unwrap_or_default();
    語.parse().map_err(|誤り| format!("{条件名}の{前置き}を数として読めない({語}): {誤り}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    const 焼いていない標本: &str = "間接照明生成パス数 数えたフレーム数=160 焼き直したフレーム数=0 総数=0\n";
    const 焼いた標本: &str = "間接照明生成パス数 数えたフレーム数=160 焼き直したフレーム数=1 総数=9\n";

    #[test]
    fn 全部0なら数えたフレーム数を返す() {
        assert_eq!(焼いていないことを確かめる(焼いていない標本, "標本"), Ok(160));
    }

    #[test]
    fn 焼き直したフレームがあれば失敗にする() {
        assert!(焼いていないことを確かめる(焼いた標本, "標本").is_err());
    }

    #[test]
    fn 行が無ければ失敗にする() {
        assert!(焼いていないことを確かめる("何もない出力\n", "標本").is_err());
    }
}
