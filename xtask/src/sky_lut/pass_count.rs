//! 大気のベイク済み画像生成パス数の報告行を読む工程。受け取るのは終了時報告と条件の名前、返すのはフレームごとの本数の列である。
//! 行の綴りは`crates/blitz_app/src/reports/atmosphere_passes.rs`の出力と一致させている。

#[cfg(test)]
mod reading_tests;

use crate::acceptance::{判定の名前, 報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

const 見出し: 報告の見出し = 報告の見出し::定数から生成する("大気のベイク済み画像生成パス数");
const 数えたフレーム数の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("数えたフレーム数");
const 総数の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("総数");
const 列の長さの鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("列の長さ");
const 列の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("列");
/// この報告の行は全項目が「鍵=値」の形で並ぶ。
const 値の結ばれ方: 鍵に値が結ばれる形 = 鍵に値が結ばれる形::等号の後ろが値である;

pub(super) struct 生成パス数の列 {
    pub(super) 数えたフレーム数: u64,
    pub(super) 総数: u64,
    pub(super) 報告された列の長さ: u64, // 報告側が数えた列の長さ。実際に読めた要素数と別に持ち、区切り欠けの食い違いを整合検査で捉える
    pub(super) フレームごと: Vec<u32>,
}

impl 生成パス数の列 {
    /// 先頭から数フレームぶんの並び。報告の文面へ載せて、判定が見た形をそのまま示す。
    pub(super) fn 先頭の並び(&self, 件数: usize) -> Vec<u32> {
        self.フレームごと.iter().copied().take(件数).collect()
    }

    /// 指定の本数だったフレームの回数。
    pub(super) fn 本数の回数(&self, 本数: u32) -> usize {
        self.フレームごと.iter().filter(|値| **値 == 本数).count()
    }
}

pub(super) fn 読む(報告: &終了時報告, 条件名: &str) -> Result<生成パス数の列, 検収エラー> {
    let 行 = 報告.見出しの1行(&見出し)?;
    Ok(生成パス数の列 {
        数えたフレーム数: 行.鍵に結ばれた数(&数えたフレーム数の鍵, 値の結ばれ方)?,
        総数: 行.鍵に結ばれた数(&総数の鍵, 値の結ばれ方)?,
        報告された列の長さ: 行.鍵に結ばれた数(&列の長さの鍵, 値の結ばれ方)?,
        フレームごと: 列を読む(&行, 条件名)?,
    })
}

fn 列を読む(行: &報告の行, 条件名: &str) -> Result<Vec<u32>, 検収エラー> {
    let 綴り = 行.鍵に結ばれた綴り(&列の鍵, 値の結ばれ方)?;
    if 綴り.is_empty() {
        return Err(列の要素の判定名(条件名).あるはずのものが無い破れ().into());
    }
    let mut 一覧 = Vec::new();
    for 語 in 綴り.split(',') {
        一覧.push(列の要素の判定名(条件名).材料を数として読む(語)?);
    }
    Ok(一覧)
}

fn 列の要素の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}の{見出し}の列の要素"))
}
