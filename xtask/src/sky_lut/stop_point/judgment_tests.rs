//! 停止点の判定の反証。担当するのは、合成の区間が立った実行・絵が一致した実行・空中遠近を焼くフレームが混じった実行を
//! それぞれ落とすことを標本で固定することである。

#![allow(clippy::unwrap_used)]

use super::super::judgment::test_series::列を作る;
use super::*;
use crate::acceptance::検収の実行名;

const 標本の実行名: 検収の実行名 = 検収の実行名::定数から生成する("sky_lut_stop_point");
const 合成なしの標本: &str = "パス別GPU時間(移動平均、60フレーム窓):\n  透過率生成: 0.1000 ms\n  スカイビュー生成: 0.3000 ms\n  空: 0.0154 ms\n";
const 合成ありの標本: &str = "パス別GPU時間(移動平均、60フレーム窓):\n  空中遠近生成: 0.4000 ms\n  空中遠近合成: 0.0500 ms\n  空: 0.0154 ms\n";

fn 報告にする(標準出力: &str) -> 終了時報告 {
    終了時報告::取り込む(&標本の実行名, 標準出力.to_string(), String::new())
}

#[test]
fn 合成の経路が走らず絵が違えば合格にする() {
    let 判定 = 停止点を判定する(&報告にする(合成なしの標本), &列を作る(vec![3, 0, 0]), &[1, 2, 3], &[1, 2, 4]);
    assert!(判定.is_ok(), "{判定:?}");
}

/// 負の対照: 合成の区間が立っていたら停止点として通さない。
#[test]
fn 合成の区間が立ったら落とす() {
    assert!(停止点を判定する(&報告にする(合成ありの標本), &列を作る(vec![3, 0, 0]), &[1, 2, 3], &[1, 2, 4]).is_err());
}

/// 負の対照: 絵が一致したら、合成が何もしていない実装を見逃さないため落とす。
#[test]
fn 絵が一致したら落とす() {
    assert!(停止点を判定する(&報告にする(合成なしの標本), &列を作る(vec![3, 0, 0]), &[1, 2, 3], &[1, 2, 3]).is_err());
}

/// 負の対照: 空中遠近を焼くフレームが混じったら落とす。
#[test]
fn 焼き直しが混じったら落とす() {
    assert!(停止点を判定する(&報告にする(合成なしの標本), &列を作る(vec![3, 1, 0]), &[1, 2, 3], &[1, 2, 4]).is_err());
}
