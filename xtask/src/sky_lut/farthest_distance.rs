//! 本番の空中遠近条件が焼きへ渡した最遠距離の読み取りと判定。受け取るのは終了時報告と条件の名前、
//! 返すのは判定が見た数を並べた文である。
//!
//! これを課すのは、逆向き深度の端点を取り違えると最遠距離が遠クリップから近クリップへ落ちるためである。
//! 落ちても空中遠近ボリュームは焼かれ、パス数の判定も停止点の判定も通る。絵は8ビットの読み戻しでは
//! ほとんど変わらないため、時刻にも量子化にも依らずこの破れを落とせる判定は数そのものの照合だけである。
//!
//! 最小と最大の両方に一致を課すのは、実行の途中で1フレームだけ別の距離が混じった場合も落とすためである。
//! 行の綴りは`crates/blitz_app/src/reports/aerial_farthest_distance.rs`の出力と一致させている。

use crate::acceptance::{判定の名前, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

const 見出し: 報告の見出し = 報告の見出し::定数から生成する("空中遠近の最遠距離");
const 組んだフレーム数の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("組んだフレーム数");
const 最小の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("最小");
const 最大の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("最大");
/// この報告の行は全項目が「鍵=値」の形で並ぶ。
const 値の結ばれ方: 鍵に値が結ばれる形 = 鍵に値が結ばれる形::等号の後ろが値である;

/// カメラの遠クリップ(`crates/blitz_engine/src/camera/projection.rs`の`遠クリップ距離`)。
/// 空中遠近ボリュームはこの距離までの空気を積む。
const 遠クリップメートル: f64 = 10000.0;
/// 許容差。逆行列と透視除算を単精度で往復するぶんの誤差であり、遠クリップの1万分の1である。
/// 端点を取り違えたときの値は近クリップの0.1メートルであり、この幅では到底収まらない。
const 許容差メートル: f64 = 1.0;

/// 空中遠近ボリュームを実際に焼く2条件の両方へ課す。合成を切った条件は空中遠近を1本も焼かないため対象にしない。
pub(super) fn 二条件が遠クリップと一致することを確かめる(
    停止の報告: &終了時報告,
    進行の報告: &終了時報告,
) -> Result<String, 検収エラー> {
    let 停止 = 遠クリップと一致することを確かめる(停止の報告, "時計停止")?;
    let 進行 = 遠クリップと一致することを確かめる(進行の報告, "時計進行")?;
    Ok(format!("{停止}、{進行}"))
}

fn 遠クリップと一致することを確かめる(報告: &終了時報告, 条件名: &str) -> Result<String, 検収エラー> {
    let 行 = 報告.見出しの1行(&見出し)?;
    let 組んだフレーム数: u64 = 行.鍵に結ばれた数(&組んだフレーム数の鍵, 値の結ばれ方)?;
    フレーム数の判定名(条件名).下限を課す(組んだフレーム数, 1)?;
    let 最小: f64 = 行.鍵に結ばれた数(&最小の鍵, 値の結ばれ方)?;
    let 最大: f64 = 行.鍵に結ばれた数(&最大の鍵, 値の結ばれ方)?;
    最小の判定名(条件名).許容の範囲を課す(最小, 下限(), 上限())?;
    最大の判定名(条件名).許容の範囲を課す(最大, 下限(), 上限())?;
    Ok(format!("{条件名}は{組んだフレーム数}フレームで最遠距離{最小}から{最大}メートル"))
}

fn 下限() -> f64 {
    遠クリップメートル - 許容差メートル
}

fn 上限() -> f64 {
    遠クリップメートル + 許容差メートル
}

fn フレーム数の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}が空中遠近条件を組んだフレーム数(零なら最遠距離を1度も測っていない)"))
}

fn 最小の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{条件名}が焼きへ渡した距離の最小(カメラの遠クリップ{遠クリップメートル}メートルと一致しなければ逆向き深度の端点を取り違えている)"
    ))
}

fn 最大の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{条件名}が焼きへ渡した距離の最大(カメラの遠クリップ{遠クリップメートル}メートルと一致しなければ逆向き深度の端点を取り違えている)"
    ))
}
