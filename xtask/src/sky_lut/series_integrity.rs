//! 報告された生成パス数の列そのものの整合を確かめる工程。受け取るのは列と条件の名前、返すのは破れた期待の説明である。
//!
//! 更新判定(`judgment`)と分けて持つのは、こちらが「その実行が検収の長さだけ描き、列が実行の全体を表しているか」を見るのに対し、あちらが「並んだ本数が更新の期待どおりか」を見るためである。列の並びだけを見る更新判定は、3フレームで終わった実行の列[3]や[3, 1]も通してしまう。数えたフレーム数・列の長さ・総数が互いに整合し、かつフレーム数が検収の指定と一致することを要求すれば、短い実行や切り詰められた列で判定が空回りしない。
//!
//! 前提: 記録側が1本ずつの列として残す上限は256フレームであり、検収の160フレームより長いため、列は実行の全フレームを覆う(`crates/blitz_render/src/renderer/pass_tally/atmosphere.rs`)。

#[cfg(test)]
mod integrity_tests;

use super::pass_count::生成パス数の列;
use super::run::フレーム数;
use crate::acceptance::{判定の名前, 判定の破れ};

pub(super) fn 列の整合を確かめる(列: &生成パス数の列, 条件名: &str) -> Result<(), 判定の破れ> {
    数えたフレーム数の判定名(条件名).一致を課す(列.数えたフレーム数, フレーム数)?;
    let 読めた長さ = u64::try_from(列.フレームごと.len()).unwrap_or(u64::MAX);
    列の長さの報告の判定名(条件名).一致を課す(列.報告された列の長さ, 読めた長さ)?;
    読めた長さの判定名(条件名).一致を課す(読めた長さ, 列.数えたフレーム数)?;
    let 合計: u64 = 列.フレームごと.iter().map(|本数| u64::from(*本数)).sum();
    総数の報告の判定名(条件名).一致を課す(列.総数, 合計)
}

fn 数えたフレーム数の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}の報告が数えたフレーム数(検収は{フレーム数}フレーム描く)"))
}

fn 列の長さの報告の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{条件名}の列の長さの報告(読めた要素数と食い違うなら区切りの欠けで列が切れている)"
    ))
}

fn 読めた長さの判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{条件名}の列から読めた要素数(数えたフレーム数と食い違うなら列が実行の全体を覆っていない)"
    ))
}

fn 総数の報告の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}の総数の報告(列の合計と食い違ってはならない)"))
}
