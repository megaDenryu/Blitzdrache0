//! 報告された生成パス数の列そのものの整合を確かめる工程。受け取るのは列と条件の名前、返すのは破れた期待の説明である。
//!
//! 更新判定(`judgment`)と分けて持つのは、こちらが「その実行が検収の長さだけ描き、列が実行の全体を表しているか」を見るのに対し、あちらが「並んだ本数が更新の期待どおりか」を見るためである。列の並びだけを見る更新判定は、3フレームで終わった実行の列[3]や[3, 1]も通してしまう。数えたフレーム数・列の長さ・総数が互いに整合し、かつフレーム数が検収の指定と一致することを要求すれば、短い実行や切り詰められた列で判定が空回りしない。
//!
//! 前提: 記録側が1本ずつの列として残す上限は256フレームであり、検収の160フレームより長いため、列は実行の全フレームを覆う(`crates/blitz_render/src/renderer/atmosphere_pass_tally.rs`)。

use super::pass_count::生成パス数の列;
use super::run::フレーム数;

pub(super) fn 列の整合を確かめる(列: &生成パス数の列, 条件名: &str) -> Result<(), String> {
    if 列.数えたフレーム数 != フレーム数 {
        return Err(format!(
            "{条件名}は{フレーム数}フレーム描くべきだが、報告が数えたフレーム数は{}である",
            列.数えたフレーム数
        ));
    }
    let 読めた長さ = u64::try_from(列.フレームごと.len()).unwrap_or(u64::MAX);
    if 列.報告された列の長さ != 読めた長さ {
        return Err(format!(
            "{条件名}の列の長さの報告{}と読めた要素数{読めた長さ}が食い違う",
            列.報告された列の長さ
        ));
    }
    if 読めた長さ != 列.数えたフレーム数 {
        return Err(format!(
            "{条件名}の列は{読めた長さ}フレームぶんで、数えたフレーム数{}の全体を覆っていない",
            列.数えたフレーム数
        ));
    }
    let 合計: u64 = 列.フレームごと.iter().map(|本数| u64::from(*本数)).sum();
    if 列.総数 != 合計 {
        return Err(format!("{条件名}の総数の報告{}と列の合計{合計}が食い違う", 列.総数));
    }
    Ok(())
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::super::judgment;
    use super::*;

    /// 数えたフレーム数・列の長さ・総数が互いに整合した列。整合の破れは検査ごとに個別へ作る。
    fn 整合した列(フレームごと: Vec<u32>) -> 生成パス数の列 {
        let 長さ = u64::try_from(フレームごと.len()).unwrap();
        生成パス数の列 {
            数えたフレーム数: 長さ,
            総数: フレームごと.iter().map(|本数| u64::from(*本数)).sum(),
            報告された列の長さ: 長さ,
            フレームごと,
        }
    }

    /// 検収の長さぶんの列。先頭だけ4本を焼き、以降は焼かない停止条件の形である。
    fn 検収の長さの列() -> 生成パス数の列 {
        let mut フレームごと = vec![0_u32; usize::try_from(フレーム数).unwrap()];
        フレームごと[0] = 4;
        整合した列(フレームごと)
    }

    #[test]
    fn 検収の長さを数えた列を通す() {
        assert!(列の整合を確かめる(&検収の長さの列(), "標本").is_ok());
    }

    /// 停止列[4]や進行列[4, 2]のように短い実行は、本数の並びを見る更新判定だけなら通ってしまう。
    #[test]
    fn 不足フレーム数で落ちる() {
        assert!(judgment::時計停止を判定する(&整合した列(vec![4])).is_ok());
        assert!(judgment::時計進行を判定する(&整合した列(vec![4, 2])).is_ok());
        assert!(列の整合を確かめる(&整合した列(vec![4]), "標本").is_err());
        assert!(列の整合を確かめる(&整合した列(vec![4, 2]), "標本").is_err());
    }

    /// 列が切り詰められて長さの報告と読めた要素数が食い違う場合。
    #[test]
    fn 列の長さの報告が読めた数と違えば落ちる() {
        let mut 列 = 検収の長さの列();
        列.フレームごと.pop();
        assert!(列の整合を確かめる(&列, "標本").is_err());
    }

    /// 上限で切り捨てられた列を実行の全体だと読み替えないための対照。
    #[test]
    fn 列が数えたフレーム数を覆っていなければ落ちる() {
        let mut 列 = 検収の長さの列();
        列.フレームごと.truncate(100);
        列.報告された列の長さ = 100;
        assert!(列の整合を確かめる(&列, "標本").is_err());
    }

    #[test]
    fn 総数が列の合計と違えば落ちる() {
        let mut 列 = 検収の長さの列();
        列.総数 += 1;
        assert!(列の整合を確かめる(&列, "標本").is_err());
    }
}
