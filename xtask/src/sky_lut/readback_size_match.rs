//! 3条件の読み戻し画像の寸法が互いに一致することの判定。受け取るのは3枚の絵、返すのは判定が見た寸法の文である。
//!
//! これを絵の判定より前に課すのは、寸法が食い違ったまま先へ進むと真因の違う失敗として現れるためである。
//! 実測では、時計停止だけが1280x719で他の2条件が1280x720になった実行があり、停止点の判定は
//! 「合成ありと合成なしの読み戻しのバイト長が食い違う」で落ちた。読み手はそこから合成の実装を疑うが、
//! 実際に起きていたのは実行中のウィンドウ寸法の変化という外的要因である。
//!
//! 寸法が変わったフレームで空中遠近を焼き直すこと自体は正しい振る舞いである。視錐台の向きが変われば
//! ボリュームの中身も変わるためである。したがってここで緩めるのは焼き直しの判定ではなく、
//! 「3条件を同じ寸法で走らせ直す」という実行の側の前提である。

use crate::acceptance::{判定の名前, 判定の破れ, 読み戻し画像};

/// 食い違ったときの真因。判定の名前へ埋めて、読み手が実装でなく実行の環境を見るようにする。
const 理由: &str = "時計停止と食い違うなら実行中にウィンドウ寸法が変わった。同じ寸法で3条件を走らせ直す";

pub(super) fn 三条件の寸法が一致することを確かめる(
    停止: &読み戻し画像,
    進行: &読み戻し画像,
    合成なし: &読み戻し画像,
) -> Result<String, 判定の破れ> {
    停止と比べる(停止, 進行, "時計進行")?;
    停止と比べる(停止, 合成なし, "合成なし")?;
    Ok(format!("3条件とも{}x{}", 停止.幅().画素数(), 停止.高さ().画素数()))
}

fn 停止と比べる(停止: &読み戻し画像, 相手: &読み戻し画像, 相手の条件名: &str) -> Result<(), 判定の破れ> {
    幅の判定名(相手の条件名).一致を課す(相手.幅().画素数(), 停止.幅().画素数())?;
    高さの判定名(相手の条件名).一致を課す(相手.高さ().画素数(), 停止.高さ().画素数())
}

fn 幅の判定名(相手の条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{相手の条件名}の読み戻しの幅({理由})"))
}

fn 高さの判定名(相手の条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{相手の条件名}の読み戻しの高さ({理由})"))
}
