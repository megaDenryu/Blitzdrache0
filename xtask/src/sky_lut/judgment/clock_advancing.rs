//! 時計を進めた条件で期待する列の形。受け取るのは列、返すのは破れた期待の説明である。
//!
//! 太陽が動くためスカイビューと空中遠近の2本を焼き直す。この条件が落とすのは「常に0本」であり、
//! 鍵の比較が変化を捉えていない欠陥をここが捉える。上限と割合の2つで見るのは、上限だけでは
//! 「1本しか焼かない(スカイビューを飛ばした)」列を通してしまうためである。

use super::{二フレーム目以降, 初回が全部であることを確かめる, 太陽が動いた本数, 生成パス数の列};

/// 太陽が動いてスカイビューを焼き直すべきフレームの割合の下限。
/// 1未満にするのは、実時間の経過が0になるフレームが混じると鍵が変わらず焼き直しが省かれるためである。
const スカイビュー割合の下限: f64 = 0.9;

pub(in crate::sky_lut) fn 時計進行を判定する(列: &生成パス数の列) -> Result<(), String> {
    初回が全部であることを確かめる(列, "時計進行")?;
    let 以降: Vec<u32> = 二フレーム目以降(列).map(|(_, 本数)| 本数).collect();
    if 以降.is_empty() {
        return Err("時計進行のフレームが1つも無い".to_string());
    }
    if let Some((添字, 本数)) = 以降.iter().enumerate().find(|(_, 本数)| **本数 > 太陽が動いた本数) {
        return Err(format!(
            "時計進行では初回の後に{太陽が動いた本数}本を超えて焼いてはならないが、フレーム{}で{本数}本焼いた",
            添字 + 1
        ));
    }
    let 焼いた数 = 以降.iter().filter(|本数| **本数 == 太陽が動いた本数).count();
    let 割合 = 割る(焼いた数, 以降.len());
    if 割合 < スカイビュー割合の下限 {
        return Err(format!(
            "時計進行では太陽が動くためスカイビューと空中遠近を焼き直すべきだが、{太陽が動いた本数}本焼いたフレームの割合が{割合:.3}で下限{スカイビュー割合の下限}未満だった"
        ));
    }
    Ok(())
}

/// 分母が0にならないことは呼び出し元が確かめているため、ここは整数から実数への変換だけを担う。
fn 割る(分子: usize, 分母: usize) -> f64 {
    let 分子 = u32::try_from(分子).unwrap_or(u32::MAX);
    let 分母 = u32::try_from(分母).unwrap_or(u32::MAX);
    f64::from(分子) / f64::from(分母)
}

