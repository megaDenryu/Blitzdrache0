//! 時計を止めた条件で期待する列の形。受け取るのは列、返すのは破れた期待の説明である。
//!
//! 大気も太陽もカメラも動かないため、初回の4本の後は1本も焼かない。この条件が落とすのは「常に4本」であり、
//! 焼き直しの省略が働いていない欠陥をここが捉える。1本(空中遠近だけ)も鍵が動いたことを意味するため不合格である。

use super::{二フレーム目以降, 全部の本数, 初回が全部であることを確かめる, 生成パス数の列};

pub(in crate::sky_lut) fn 時計停止を判定する(列: &生成パス数の列) -> Result<(), String> {
    初回が全部であることを確かめる(列, "時計停止")?;
    let 例外: Vec<(usize, u32)> = 二フレーム目以降(列).filter(|(_, 本数)| *本数 != 0).collect();
    if !例外.is_empty() {
        return Err(format!(
            "時計停止では初回の{全部の本数}本の後は0本であるべきだが、0本でないフレームが{}件あった(先頭{:?})",
            例外.len(),
            例外.iter().take(4).collect::<Vec<_>>()
        ));
    }
    Ok(())
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::super::test_series::列を作る;
    use super::*;

    #[test]
    fn 初回だけ四本を許す() {
        assert!(時計停止を判定する(&列を作る(vec![4, 0, 0])).is_ok());
        assert!(時計停止を判定する(&列を作る(vec![4, 2, 0])).is_err());
        assert!(時計停止を判定する(&列を作る(vec![0, 0, 0])).is_err());
    }

    /// カメラだけが動いた1本のフレームも、時計停止では鍵が動かないはずであるため不合格である。
    #[test]
    fn 空中遠近だけの一本も落とす() {
        assert!(時計停止を判定する(&列を作る(vec![4, 1, 0])).is_err());
    }
}
