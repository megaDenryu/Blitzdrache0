//! 1条件ぶんの本数が更新計画どおりであることの判定。担当する工程は「読み取り済みの実測と見込みと区間の変化回数を
//! 受け取り、その条件の焼き方に対して本数が計画どおりかを確かめる」ことであり、報告を1行も読まない。
//!
//! 読み取りと分けてあるのは、行を先に読んでおきたい呼び出し元(`indirect-cost`)が同じ期待の組み立てを
//! 二重に持たずに済むようにするためである。3条件を並べて確かめる工程は親モジュールが持つ。

use super::rows::{実測, 見込み};
use super::焼き方;
use crate::acceptance::{判定の名前, 判定の破れ};

pub(crate) fn 本数を確かめる(
    実測: 実測, 見込み: 見込み, 条件名: &str, 焼き方: 焼き方, 区間の変化回数: u64
) -> Result<(), 判定の破れ> {
    // 1フレームも数えていない実行は、初回のフレームが焼いたかどうかを判定できない。総数0を素通しにしない。
    if 実測.数えたフレーム数 == 0 {
        return Err(数えたフレームの判定名(条件名).あるはずのものが無い破れ());
    }
    区間の変化を確かめる(条件名, 焼き方, 区間の変化回数)?;
    let 焼くフレーム数 = 区間の変化回数 + 1;
    焼き直したフレーム数の判定名(条件名, 区間の変化回数).一致を課す(実測.焼き直したフレーム数, 焼くフレーム数)?;
    総数の判定名(条件名).一致を課す(実測.総数, 見込み.初回の合計 + 見込み.焼き直しの合計 * (焼くフレーム数 - 1))
}

/// その条件が要求する区間の動き方。時計を止めた条件で区間が動くのは時刻が進んでいることを、時計を進めた条件で
/// 1度も動かないのは太陽が動いていないか刻みが粗すぎることを意味し、どちらも測るべき状態を測っていない。
fn 区間の変化を確かめる(条件名: &str, 焼き方: 焼き方, 区間の変化回数: u64) -> Result<(), 判定の破れ> {
    match 焼き方 {
        焼き方::初回だけ => 太陽が動かない条件の判定名(条件名).零件であることを課す(区間の変化回数),
        焼き方::区間が変わるたび => 太陽が動く条件の判定名(条件名).下限を課す(区間の変化回数, 1),
    }
}

fn 数えたフレームの判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}の間接照明が数えたフレーム"))
}

fn 焼き直したフレーム数の判定名(条件名: &str, 区間の変化回数: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{条件名}の焼き直したフレーム数(期待は区間の変化{区間の変化回数}回に初回の1回を足した数である)"
    ))
}

fn 総数の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}の生成パスの総数"))
}

fn 太陽が動かない条件の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}(太陽が動かない条件)で太陽天頂区間が変わった回数"))
}

fn 太陽が動く条件の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{条件名}(太陽が動く条件)で太陽天頂区間が変わった回数(0なら太陽が動いていないか刻みが粗すぎる)"
    ))
}
