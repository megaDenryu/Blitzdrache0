//! 間接照明の生成パス数の判定を、標本の標準出力で反証する検査。
//! 見込みの行を実測と食い違わせた標本を作れることが、この判定が期待を検収側で組み立てていないことの裏返しである。
//! 同じく、区間の変化回数と焼き直したフレーム数を食い違わせた標本を落とすことが、間引きの効きを見ている裏返しである。

use super::*;

/// 既定の粗さ段数6段で本番の計画が答える本数(初回10本・焼き直し9本)。
const 見込みの行: &str = "間接照明生成パス数の見込み 契約=遠方環境 初回の合計=10 焼き直しの合計=9\n";

fn 出力(数えたフレーム数: u64, 焼き直したフレーム数: u64, 総数: u64, 区間の変化回数: u64) -> String {
    format!(
        "間接照明生成パス数 数えたフレーム数={数えたフレーム数} 焼き直したフレーム数={焼き直したフレーム数} 総数={総数}\n{見込みの行}太陽天頂区間 判定したフレーム数={数えたフレーム数} 区間が変わった回数={区間の変化回数} 直近の区間識別=42\n"
    )
}

fn 停止の正例() -> String {
    出力(160, 1, 10, 0)
}

/// 160フレームのうち20回だけ区間を跨いだ実行。間引きが効いていれば焼くのは21フレームである。
fn 進行の正例() -> String {
    出力(160, 21, 10 + 9 * 20, 20)
}

#[test]
fn 三条件が計画どおりなら要約を返す() {
    let 結果 = 三条件を確かめる(&停止の正例(), &進行の正例(), &停止の正例());
    assert!(結果.is_ok(), "{結果:?}");
}

#[test]
fn 時計停止で区間が動いていたら失敗にする() {
    assert!(三条件を確かめる(&進行の正例(), &進行の正例(), &停止の正例()).is_err());
}

#[test]
fn 時計進行で区間が1度も動いていなかったら失敗にする() {
    assert!(三条件を確かめる(&停止の正例(), &停止の正例(), &停止の正例()).is_err());
}

/// 区間が20回しか変わっていないのに毎フレーム焼いた実行は、間引きが1つも効いていないことを意味する。
#[test]
fn 区間の変化より多く焼いていたら失敗にする() {
    let 間引かない = 出力(160, 160, 10 + 9 * 159, 20);
    assert!(三条件を確かめる(&停止の正例(), &間引かない, &停止の正例()).is_err());
}

#[test]
fn 総数が見込みと食い違えば失敗にする() {
    assert!(三条件を確かめる(&出力(160, 1, 9, 0), &進行の正例(), &停止の正例()).is_err());
}

#[test]
fn 定数近似の契約なら失敗にする() {
    let 定数近似 = "間接照明生成パス数 数えたフレーム数=160 焼き直したフレーム数=0 総数=0\n間接照明生成パス数の見込み 契約=定数近似\n";
    assert!(三条件を確かめる(定数近似, &進行の正例(), &停止の正例()).is_err());
}

#[test]
fn 条件ごとに見込みが違えば失敗にする() {
    let 別の見込み = "間接照明生成パス数 数えたフレーム数=160 焼き直したフレーム数=1 総数=8\n間接照明生成パス数の見込み 契約=遠方環境 初回の合計=8 焼き直しの合計=7\n太陽天頂区間 判定したフレーム数=160 区間が変わった回数=0 直近の区間識別=42\n";
    assert!(三条件を確かめる(&停止の正例(), &進行の正例(), 別の見込み).is_err());
}

/// 太陽天頂区間の行が無い出力は、間引きの記録を出さない古い本番と組み合わさっていることを意味する。
#[test]
fn 区間の行が無ければ失敗にする() {
    let 区間なし = format!("間接照明生成パス数 数えたフレーム数=160 焼き直したフレーム数=1 総数=10\n{見込みの行}");
    assert!(三条件を確かめる(&区間なし, &進行の正例(), &停止の正例()).is_err());
}

#[test]
fn 行が無ければ失敗にする() {
    assert!(三条件を確かめる("何もない出力\n", &進行の正例(), &停止の正例()).is_err());
}
