//! 間接照明の生成パス数の判定を、標本の標準出力で反証する検査。
//! 見込みの行を実測と食い違わせた標本を作れることが、この判定が期待を検収側で組み立てていないことの裏返しである。

use super::*;

/// 既定の粗さ段数6段で本番の計画が答える本数(初回9本・焼き直し8本)。
const 見込みの行: &str = "間接照明生成パス数の見込み 契約=遠方環境 初回の合計=9 焼き直しの合計=8\n";

fn 出力(数えたフレーム数: u64, 焼き直したフレーム数: u64, 総数: u64) -> String {
    format!("間接照明生成パス数 数えたフレーム数={数えたフレーム数} 焼き直したフレーム数={焼き直したフレーム数} 総数={総数}\n{見込みの行}")
}

fn 停止の正例() -> String {
    出力(160, 1, 9)
}

fn 進行の正例() -> String {
    出力(160, 160, 9 + 8 * 159)
}

#[test]
fn 三条件が計画どおりなら要約を返す() {
    let 結果 = 三条件を確かめる(&停止の正例(), &進行の正例(), &停止の正例());
    assert!(結果.is_ok(), "{結果:?}");
}

#[test]
fn 時計停止で毎フレーム焼いていたら失敗にする() {
    assert!(三条件を確かめる(&進行の正例(), &進行の正例(), &停止の正例()).is_err());
}

#[test]
fn 時計進行で初回しか焼いていなかったら失敗にする() {
    assert!(三条件を確かめる(&停止の正例(), &停止の正例(), &停止の正例()).is_err());
}

#[test]
fn 総数が見込みと食い違えば失敗にする() {
    assert!(三条件を確かめる(&出力(160, 1, 8), &進行の正例(), &停止の正例()).is_err());
}

#[test]
fn 定数近似の契約なら失敗にする() {
    let 定数近似 = "間接照明生成パス数 数えたフレーム数=160 焼き直したフレーム数=0 総数=0\n間接照明生成パス数の見込み 契約=定数近似\n";
    assert!(三条件を確かめる(定数近似, &進行の正例(), &停止の正例()).is_err());
}

#[test]
fn 条件ごとに見込みが違えば失敗にする() {
    let 別の見込み = "間接照明生成パス数 数えたフレーム数=160 焼き直したフレーム数=1 総数=7\n間接照明生成パス数の見込み 契約=遠方環境 初回の合計=7 焼き直しの合計=6\n";
    assert!(三条件を確かめる(&停止の正例(), &進行の正例(), 別の見込み).is_err());
}

#[test]
fn 行が無ければ失敗にする() {
    assert!(三条件を確かめる("何もない出力\n", &進行の正例(), &停止の正例()).is_err());
}
