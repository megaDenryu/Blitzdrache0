//! 間接照明の報告の行を数へ写す工程。受け取るのは1条件ぶんの標準出力と条件の名前、返すのは実測の3つの数と
//! 見込みの2つの数である。行の綴りは`crates/blitz_app/src/reports/atmosphere_passes.rs`の出力と一致させている。
//!
//! 読み取りを判定と別のファイルへ置くのは、直す理由が違うためである。綴りが変わったときに直すのはここだけであり、
//! 条件ごとの期待が変わったときに直すのは判定だけである。

/// 1条件ぶんの実測。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 実測 {
    pub(crate) 数えたフレーム数: u64,
    pub(crate) 焼き直したフレーム数: u64,
    pub(crate) 総数: u64,
}

/// 本番の焼き上げの計画が答えた、1フレームぶんに積む本数。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 見込み {
    pub(crate) 初回の合計: u64,
    pub(crate) 焼き直しの合計: u64,
}

/// 実測の行の先頭。末尾の空白まで含めるのは、見込みの行が同じ語で始まるためである。
const 実測の先頭: &str = "間接照明生成パス数 ";
const 見込みの先頭: &str = "間接照明生成パス数の見込み ";
/// 見込みの行が遠方環境の契約であることを示す語。定数近似の実行はこの語を持たない。
const 遠方環境の契約: &str = "契約=遠方環境";

pub(crate) fn 実測を読む(標準出力: &str, 条件名: &str) -> Result<実測, String> {
    let 行 = 行を探す(標準出力, 実測の先頭, 条件名)?;
    Ok(実測 {
        数えたフレーム数: 数を読む(行, "数えたフレーム数=", 条件名)?,
        焼き直したフレーム数: 数を読む(行, "焼き直したフレーム数=", 条件名)?,
        総数: 数を読む(行, "総数=", 条件名)?,
    })
}

/// 見込みの行を読む。契約が定数近似だと1フレームぶんの本数が無く、地形世界が遠方環境へ切り替わっていないことを
/// 意味するため、そこで失敗にする。
pub(crate) fn 見込みを読む(標準出力: &str, 条件名: &str) -> Result<見込み, String> {
    let 行 = 行を探す(標準出力, 見込みの先頭, 条件名)?;
    if !行.contains(遠方環境の契約) {
        return Err(format!("{条件名}の見込みの行が遠方環境の契約でない: {行}"));
    }
    Ok(見込み {
        初回の合計: 数を読む(行, "初回の合計=", 条件名)?,
        焼き直しの合計: 数を読む(行, "焼き直しの合計=", 条件名)?,
    })
}

fn 行を探す<'出力>(標準出力: &'出力 str, 先頭: &str, 条件名: &str) -> Result<&'出力 str, String> {
    標準出力
        .lines()
        .find(|行| 行.starts_with(先頭))
        .ok_or_else(|| format!("{条件名}の出力に{}で始まる行が無い", 先頭.trim_end()))
}

fn 数を読む(行: &str, 前置き: &str, 条件名: &str) -> Result<u64, String> {
    let 残り = 行
        .split(前置き)
        .nth(1)
        .ok_or_else(|| format!("{条件名}の間接照明の行に{前置き}が無い: {行}"))?;
    let 語 = 残り.split_whitespace().next().unwrap_or_default();
    語.parse().map_err(|誤り| format!("{条件名}の{前置き}を数として読めない({語}): {誤り}"))
}
