//! 間接照明の報告の行を数へ写す工程。受け取るのは1条件ぶんの終了時報告、返すのは実測の3つの数と
//! 見込みの2つの数である。行の綴りは`crates/blitz_app/src/reports/atmosphere_passes.rs`の出力と一致させている。
//!
//! 読み取りを判定と別のファイルへ置くのは、直す理由が違うためである。綴りが変わったときに直すのはここだけであり、
//! 条件ごとの期待が変わったときに直すのは判定だけである。
//!
//! 行が無いことの文面が条件を名指せるのは、終了時報告が実行名を一緒に持つためである。条件の名前を引数で運ぶのは、
//! 契約の食い違いのように読み取りでなく判定として落とす1箇所だけである。

use crate::acceptance::{判定の名前, 報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

/// 1条件ぶんの実測。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 実測 {
    pub(crate) 数えたフレーム数: u64,
    pub(crate) 焼き直したフレーム数: u64,
    pub(crate) 総数: u64,
}

/// 本番の焼き上げの計画が答えた、1フレームぶんに積む本数。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 見込み {
    pub(crate) 初回の合計: u64,
    pub(crate) 焼き直しの合計: u64,
}

/// 実測の行の見出し。末尾の空白まで含めるのは、見込みの行が同じ語で始まるためである。
const 実測の見出し: 報告の見出し = 報告の見出し::定数から生成する("間接照明生成パス数 ");
const 見込みの見出し: 報告の見出し = 報告の見出し::定数から生成する("間接照明生成パス数の見込み ");
/// 太陽天頂区間の記録の行の見出し。綴りは`crates/blitz_app/src/reports/distant_environment_key.rs`の出力と一致させている。
const 区間の見出し: 報告の見出し = 報告の見出し::定数から生成する("太陽天頂区間 ");

const 契約の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("契約");
/// 見込みの行が遠方環境の契約であることを示す語。定数近似の実行はこの語を持たない。
const 遠方環境の契約: &str = "遠方環境";
/// この報告の行は全項目が「鍵=値」の形で並ぶ。
const 値の結ばれ方: 鍵に値が結ばれる形 = 鍵に値が結ばれる形::等号の後ろが値である;

pub(crate) fn 実測を読む(報告: &終了時報告) -> Result<実測, 検収エラー> {
    let 行 = 報告.見出しの1行(&実測の見出し)?;
    Ok(実測 {
        数えたフレーム数: 数を読む(&行, "数えたフレーム数")?,
        焼き直したフレーム数: 数を読む(&行, "焼き直したフレーム数")?,
        総数: 数を読む(&行, "総数")?,
    })
}

/// 見込みの行を読む。契約が定数近似だと1フレームぶんの本数が無く、地形世界が遠方環境へ切り替わっていないことを
/// 意味するため、そこで失敗にする。
pub(crate) fn 見込みを読む(報告: &終了時報告, 条件名: &str) -> Result<見込み, 検収エラー> {
    let 行 = 報告.見出しの1行(&見込みの見出し)?;
    let 契約 = 行.鍵に結ばれた綴り(&契約の鍵, 値の結ばれ方)?;
    契約の判定名(条件名).綴りの一致を課す(&契約, 遠方環境の契約)?;
    Ok(見込み {
        初回の合計: 数を読む(&行, "初回の合計")?,
        焼き直しの合計: 数を読む(&行, "焼き直しの合計")?,
    })
}

/// 太陽天頂区間が前のフレームから変わった回数。遠方環境を焼き直すべきフレーム数はこの値に初回の1回を足したものである。
pub(crate) fn 区間の変化回数を読む(報告: &終了時報告) -> Result<u64, 検収エラー> {
    数を読む(&報告.見出しの1行(&区間の見出し)?, "区間が変わった回数")
}

fn 数を読む(行: &報告の行, 鍵: &'static str) -> Result<u64, 検収エラー> {
    行.鍵に結ばれた数(&報告の行の鍵::定数から生成する(鍵), 値の結ばれ方)
}

fn 契約の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{条件名}の間接照明生成パス数の見込みの行の契約(定数近似なら地形世界が遠方環境へ切り替わっていない)"
    ))
}
