//! 大気の各区間が別々に立っていることの確認と、空の定常予算との比較。
//! 受け取るのは終了時報告、返すのは区間名とミリ秒を並べた文と定常合計である。表の読み取りは`table`が持つ。
//!
//! 区間を個別に立てることは設計正本が要求しており(「予算と計器」)、区間名はレンダーグラフのパス名そのままである。
//!
//! 定常予算へ入れるのは毎フレーム走る区間だけである。透過率生成と多重散乱生成は大気が変わったフレームだけの
//! 更新時予算であり、定常平均へ隠さない。

#[cfg(test)]
mod interval_tests;

mod table;

use crate::acceptance::{判定の名前, 検収エラー, 終了時報告};

/// 空の定常予算。毎フレーム走る区間の合計がこれを超えたら報告で告知する。
pub(crate) const 空の定常予算ミリ秒: f64 = 1.0;

/// 大気が変わったフレームだけ走る区間。移動平均の表は走らなくなった区間の最後の標本を保つため、
/// 毎フレームの費用として足してはならない。
pub(crate) const 更新時の区間一覧: [&str; 2] = ["透過率生成", "多重散乱生成"];
/// 毎フレーム走る区間。この2つの台帳と上の予算は`ow4-bench`も読む(同じ集合と同じ予算を2箇所で決めない)。
pub(crate) const 定常の区間一覧: [&str; 4] = ["スカイビュー生成", "空中遠近生成", "空中遠近合成", "空"];

pub(super) struct 計器の読み {
    pub(super) 区間の並び: String,
    pub(super) 定常の合計ミリ秒: f64,
}

impl 計器の読み {
    /// 定常予算との比較を1文で表す。超過は隠さず語で示す。
    pub(super) fn 予算との比較(&self) -> String {
        let 判定 = if self.定常の合計ミリ秒 <= 空の定常予算ミリ秒 {
            "予算内"
        } else {
            "予算超過"
        };
        format!("定常合計{:.4}ms(予算{空の定常予算ミリ秒:.1}ms・{判定})", self.定常の合計ミリ秒)
    }
}

/// 表に区間が1つも現れないことを確かめる。合成を切った実行が合成の経路を1本も走らせないことの判定に使う。
/// パス名がそのまま区間名になるため、行の不在はパスがグラフへ積まれていないことを意味する。
pub(super) fn 区間が無いことを確かめる(報告: &終了時報告, 無いはずの区間: &[&str]) -> Result<(), 検収エラー> {
    let 表 = table::読む(報告)?;
    for 区間名 in 無いはずの区間 {
        let 現れた本数 = u64::from(table::区間を探す(&表, 区間名).is_some());
        現れてはならない区間の判定名(区間名).零件であることを課す(現れた本数)?;
    }
    Ok(())
}

pub(super) fn 区間を読む(報告: &終了時報告) -> Result<計器の読み, 検収エラー> {
    let 表 = table::読む(報告)?;
    let mut 並び = Vec::new();
    for 区間名 in 更新時の区間一覧.iter().chain(定常の区間一覧.iter()) {
        並び.push(format!("{区間名}{:.4}ms", table::区間を参照する(&表, 区間名)?));
    }
    let mut 定常の合計ミリ秒 = 0.0;
    for 区間名 in 定常の区間一覧 {
        定常の合計ミリ秒 += table::区間を参照する(&表, 区間名)?;
    }
    Ok(計器の読み {
        区間の並び: 並び.join("・"),
        定常の合計ミリ秒,
    })
}

fn 現れてはならない区間の判定名(区間名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("合成を切った実行に現れた区間{区間名}"))
}
