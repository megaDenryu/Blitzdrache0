//! 大気の各区間が別々に立っていることの確認と、空の定常予算との比較。
//! 受け取るのは標準出力、返すのは区間名とミリ秒を並べた文と定常合計である。表の読み取りは`table`が持つ。
//!
//! 区間を個別に立てることは設計正本が要求しており(「予算と計器」)、区間名はレンダーグラフのパス名そのままである。
//!
//! 定常予算へ入れるのは毎フレーム走る区間だけである。透過率生成と多重散乱生成は大気が変わったフレームだけの
//! 更新時予算であり、定常平均へ隠さない。

mod table;

/// 空の定常予算。毎フレーム走る区間の合計がこれを超えたら報告で告知する。
const 空の定常予算ミリ秒: f64 = 1.0;

const 区間名一覧: [&str; 6] = ["透過率生成", "多重散乱生成", "スカイビュー生成", "空中遠近生成", "空中遠近合成", "空"];
/// 毎フレーム走る区間。透過率生成と多重散乱生成だけが更新時であり、残りの4つは毎フレーム走る。
const 定常の区間一覧: [&str; 4] = ["スカイビュー生成", "空中遠近生成", "空中遠近合成", "空"];

pub(super) struct 計器の読み {
    pub(super) 区間の並び: String,
    pub(super) 定常の合計ミリ秒: f64,
}

impl 計器の読み {
    /// 定常予算との比較を1文で表す。超過は隠さず語で示す。
    pub(super) fn 予算との比較(&self) -> String {
        let 判定 = if self.定常の合計ミリ秒 <= 空の定常予算ミリ秒 {
            "予算内"
        } else {
            "予算超過"
        };
        format!("定常合計{:.4}ms(予算{空の定常予算ミリ秒:.1}ms・{判定})", self.定常の合計ミリ秒)
    }
}

/// 表に区間が1つも現れないことを確かめる。合成を切った実行が合成の経路を1本も走らせないことの判定に使う。
/// パス名がそのまま区間名になるため、行の不在はパスがグラフへ積まれていないことを意味する。
pub(super) fn 区間が無いことを確かめる(標準出力: &str, 無いはずの区間: &[&str]) -> Result<(), String> {
    let 表 = table::読む(標準出力)?;
    for 区間名 in 無いはずの区間 {
        if table::区間を参照する(&表, 区間名).is_ok() {
            return Err(format!("合成を切った実行に区間{区間名}が現れた"));
        }
    }
    Ok(())
}

pub(super) fn 区間を読む(標準出力: &str) -> Result<計器の読み, String> {
    let 表 = table::読む(標準出力)?;
    let mut 並び = Vec::new();
    for 区間名 in 区間名一覧 {
        並び.push(format!("{区間名}{:.4}ms", table::区間を参照する(&表, 区間名)?));
    }
    let mut 定常の合計ミリ秒 = 0.0;
    for 区間名 in 定常の区間一覧 {
        定常の合計ミリ秒 += table::区間を参照する(&表, 区間名)?;
    }
    Ok(計器の読み {
        区間の並び: 並び.join("・"),
        定常の合計ミリ秒,
    })
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    const 標本: &str = "パス別GPU時間(移動平均、60フレーム窓):\n  透過率生成: 0.1000 ms\n  多重散乱生成: 0.2000 ms\n  スカイビュー生成: 0.3000 ms\n  空中遠近生成: 0.4000 ms\n  空中遠近合成: 0.0500 ms\n  空: 0.0154 ms\n";

    #[test]
    fn 六区間を並べる() {
        let 読み = 区間を読む(標本).unwrap();
        assert!(読み.区間の並び.contains("透過率生成0.1000ms"), "{}", 読み.区間の並び);
        assert!(読み.区間の並び.contains("空中遠近生成0.4000ms"), "{}", 読み.区間の並び);
        assert!(読み.区間の並び.contains("空中遠近合成0.0500ms"), "{}", 読み.区間の並び);
        assert!(読み.区間の並び.contains("空0.0154ms"), "{}", 読み.区間の並び);
    }

    /// 定常合計へ入るのはスカイビュー生成・空中遠近生成・空中遠近合成・空の4つだけであり、更新時の2つは入らない。
    #[test]
    fn 定常合計は更新時の区間を含めない() {
        let 読み = 区間を読む(標本).unwrap();
        assert!((読み.定常の合計ミリ秒 - 0.7654).abs() < 1.0e-9, "{}", 読み.定常の合計ミリ秒);
        assert!(読み.予算との比較().contains("予算内"), "{}", 読み.予算との比較());
    }

    #[test]
    fn 区間が欠けたら失敗にする() {
        assert!(区間を読む("パス別GPU時間:\n  空: 0.0154 ms\n").is_err());
    }

    /// 合成を切った実行の判定に使う側。表に無い区間を「無い」と答え、在る区間を見つけたら落とす。
    #[test]
    fn 無いはずの区間が在れば落とす() {
        assert!(区間が無いことを確かめる(標本, &["粒子"]).is_ok());
        assert!(区間が無いことを確かめる(標本, &["空中遠近合成"]).is_err());
    }
}
