//! 検収1条件ぶんの起動の指定。受け取るのは条件と一日内秒、返すのは実行環境へ渡す起動指定である。
//! 起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! 地形世界は空を持つ方針であるため、空ありの指定は足さない。足すのは2つの報告の指定だけである。
//! 地形世界は本番のストリーミング経路でしか地面が現れないため、先読み半径と容量上限をOW3の統合経路と同じ値で渡す。
//! カメラはシーン既定の見下ろし35度のままだと視野が地平線より下に収まるため、25度戻して地平線より上を画面へ入れる。
//! 時間再構成は`--no-taa`で外す。この入口の判定がバイト一致に依るため、フレームをまたぐ混合が入ると前のフレームの残りが絵に混ざる。

use std::path::PathBuf;

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収の1回の実行, 検収の実行名, 検収エラー,
    検収シーン名,
};
use crate::verify::検証の出力ルート;

const シーン名: 検収シーン名 = 検収シーン名::生成する("terrain_origin");
/// 1条件ぶんに描くフレーム数。列の整合検査もこの値を読み、報告が本当にこの本数を数えたことを確かめる。
pub(super) const フレーム数: u64 = 160;
const 描く枚数: 描画フレーム数 = 描画フレーム数::生成する(160);
const 先読み半径: &str = "2";
const 容量上限バイト: &str = "16777216";
const カメラ俯角差分度: &str = "-25";
/// 時計を進める条件の倍率。実時間1秒で1時間ぶん進めるため、1フレーム(16ミリ秒程度)でも太陽の天頂余弦が
/// f32のビット表現で必ず変わる。小さい倍率では変わらないフレームが混じり、スカイビューの焼き直しが飛ぶ。
const 時間倍率: &str = "3600";
const 報告を出させる選択肢: [&str; 2] = ["--report-atmosphere-passes", "--report-gpu-times"];

/// 3条件の書き出しの基準名。絵のファイル名になり、失敗の文面もこの名前で実行を名指す。
pub(super) const 時計停止の実行名: 検収の実行名 = 検収の実行名::定数から生成する("lut_stopped");
pub(super) const 時計進行の実行名: 検収の実行名 = 検収の実行名::定数から生成する("lut_advancing");
pub(super) const 合成なしの実行名: 検収の実行名 = 検収の実行名::定数から生成する("lut_no_composite");

#[derive(Clone, Copy)]
pub(super) enum 条件 {
    時計停止, // 時計を止めたまま描く。初回のフレームだけが4本を焼き、以降は1本も焼かないことを見る
    時計進行, // 時計を進めて描く。太陽が動くフレームがスカイビューと空中遠近を焼き直すことを見る
    合成なし, // 時計を止めたまま合成を切って描く。合成の経路が1本も走らず、絵が合成ありと違うことを見る
}

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::パスから生成する(
            検証の出力ルート::既定().名前が指す置き場(crate::compile_assets::地形の世界の実行時形式の置き場),
        ),
        出力ディレクトリ,
    )
}

pub(super) fn 描く(
    実行環境: &描画検収の実行環境,
    実行名: 検収の実行名,
    条件: 条件,
    一日内秒: Option<&str>,
) -> Result<検収の1回の実行, 検収エラー> {
    実行環境.描いて読み戻す(実行名, &起動指定を組み立てる(条件, 一日内秒))
}

fn 起動指定を組み立てる(条件: 条件, 一日内秒: Option<&str>) -> アプリの起動指定 {
    let 指定 = アプリの起動指定::シーンと枚数を決める(シーン名, 描く枚数)
        .選択肢を足す("--streaming")
        .値を持つ選択肢を足す("--streaming-preload-radius", 先読み半径)
        .値を持つ選択肢を足す("--streaming-ram-limit", 容量上限バイト)
        .値を持つ選択肢を足す("--streaming-vram-limit", 容量上限バイト)
        .値を持つ選択肢を足す("--camera-pitch", カメラ俯角差分度)
        .選択肢をまとめて足す(&報告を出させる選択肢)
        .選択肢をまとめて足す(条件別の選択肢(条件));
    let Some(秒) = 一日内秒 else {
        return 指定.選択肢を足す("--no-taa");
    };
    指定.値を持つ選択肢を足す("--time-of-day", 秒).選択肢を足す("--no-taa")
}

fn 条件別の選択肢(条件: 条件) -> &'static [&'static str] {
    match 条件 {
        条件::時計停止 => &[],
        条件::時計進行 => &["--time-scale", 時間倍率],
        条件::合成なし => &["--no-aerial-composite"],
    }
}
