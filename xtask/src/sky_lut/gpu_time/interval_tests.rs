//! 区間の読み取りと定常合計の導出の検査。担当するのは「6区間を並べること」「定常合計へ更新時の2区間を入れないこと」
//! 「区間が欠けたら落とすこと」「無いはずの区間が在れば落とすこと」を標本で固定することである。

#![allow(clippy::unwrap_used)]

use super::*;
use crate::acceptance::検収の実行名;

const 標本の実行名: 検収の実行名 = 検収の実行名::定数から生成する("sky_lut_gpu_time");
const 標本: &str = "パス別GPU時間(移動平均、60フレーム窓):\n  透過率生成: 0.1000 ms\n  多重散乱生成: 0.2000 ms\n  スカイビュー生成: 0.3000 ms\n  空中遠近生成: 0.4000 ms\n  空中遠近合成: 0.0500 ms\n  空: 0.0154 ms\n";

fn 報告にする(標準出力: &str) -> 終了時報告 {
    終了時報告::取り込む(&標本の実行名, 標準出力.to_string(), String::new())
}

#[test]
fn 六区間を並べる() {
    let 読み = 区間を読む(&報告にする(標本)).unwrap();
    assert!(読み.区間の並び.contains("透過率生成0.1000ms"), "{}", 読み.区間の並び);
    assert!(読み.区間の並び.contains("空中遠近生成0.4000ms"), "{}", 読み.区間の並び);
    assert!(読み.区間の並び.contains("空中遠近合成0.0500ms"), "{}", 読み.区間の並び);
    assert!(読み.区間の並び.contains("空0.0154ms"), "{}", 読み.区間の並び);
}

/// 定常合計へ入るのはスカイビュー生成・空中遠近生成・空中遠近合成・空の4つだけであり、更新時の2つは入らない。
#[test]
fn 定常合計は更新時の区間を含めない() {
    let 読み = 区間を読む(&報告にする(標本)).unwrap();
    assert!((読み.定常の合計ミリ秒 - 0.7654).abs() < 1.0e-9, "{}", 読み.定常の合計ミリ秒);
    assert!(読み.予算との比較().contains("予算内"), "{}", 読み.予算との比較());
}

#[test]
fn 区間が欠けたら失敗にする() {
    assert!(区間を読む(&報告にする("パス別GPU時間:\n  空: 0.0154 ms\n")).is_err());
}

/// 合成を切った実行の判定に使う側。表に無い区間を「無い」と答え、在る区間を見つけたら落とす。
#[test]
fn 無いはずの区間が在れば落とす() {
    assert!(区間が無いことを確かめる(&報告にする(標本), &["粒子"]).is_ok());
    assert!(区間が無いことを確かめる(&報告にする(標本), &["空中遠近合成"]).is_err());
}
