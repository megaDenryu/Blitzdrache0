//! パス別GPU時間の報告の表を読む工程。受け取るのは終了時報告、返すのは区間名とミリ秒の対の一覧である。
//!
//! 表の書式をここが単独で持つのは、これが`--report-gpu-times`の出力との唯一の接点だからである。
//! 見出しの行に続く、見出しより深く字下げされた行が表であり、字下げが切れたところで表が終わる。
//!
//! 区間の集合は実行の構成で変わるため、名前を型で数え上げず表として持つ。

use crate::acceptance::{判定の名前, 判定の破れ, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

const 見出し: 報告の見出し = 報告の見出し::定数から生成する("パス別GPU時間");

pub(super) fn 読む(報告: &終了時報告) -> Result<Vec<(String, f64)>, 検収エラー> {
    let mut 表 = Vec::new();
    for 行 in 報告.見出しの区画(見出し)?.行一覧() {
        let Some((名前, _)) = 行.原文().trim_start().split_once(':') else {
            continue;
        };
        let 鍵 = 報告の行の鍵::組み立てた綴りから生成する(format!("{名前}:"));
        表.push((名前.to_string(), 行.鍵に結ばれた数(&鍵, 鍵に値が結ばれる形::次の語が値である)?));
    }
    Ok(表)
}

/// 名前で区間を探す。無いことを失敗と読み替えず、無いことを返す。
/// 区間が在ってはならないことを見る判定と、在らねばならないことを見る判定の両方がこの口を通る。
pub(super) fn 区間を探す(表: &[(String, f64)], 区間名: &str) -> Option<f64> {
    表.iter().find(|(名前, _)| 名前 == 区間名).map(|(_, ミリ秒)| *ミリ秒)
}

/// 名前で区間を参照する。欠けているのは、そのパスが積まれていないか区間名が変わったことを意味するため失敗にする。
pub(super) fn 区間を参照する(表: &[(String, f64)], 区間名: &str) -> Result<f64, 判定の破れ> {
    区間を探す(表, 区間名).ok_or_else(|| 区間の判定名(区間名).あるはずのものが無い破れ())
}

fn 区間の判定名(区間名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{見出し}の表の区間{区間名}"))
}
