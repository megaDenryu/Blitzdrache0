//! ソースアセットの生成器へ場所巡りの世界を書き出させる工程。受け取るのは乱数の種と、指定するならソースルート、
//! 返すのは取り込んだ標準出力である。起こし方と選択肢の綴りは`asset_generator`の器が持つ。
//!
//! 標準出力を取り込むのは、増分が効いたかを外から見る唯一の材料が生成器の報告の行だからである。
//! 取り込んだ内容はそのまま表示するため、呼び出し側の画面に出るものは流したときと変わらない。

use blitz_asset_compiler::{ソースルート, マップ生成の乱数の種, 世界の広がり};

use crate::asset_generator::{アセット生成器の起動, 生成の指定, 生成器エラー};

pub fn 既定のソースルートへ書き出す(種: マップ生成の乱数の種) -> Result<String, 生成器エラー> {
    書き出させる(種, None, None)
}

pub fn ソースルートと広がりを指定して書き出す(
    種: マップ生成の乱数の種,
    ソースルート: &ソースルート,
    広がり: 世界の広がり,
) -> Result<String, 生成器エラー> {
    書き出させる(種, Some(ソースルート), Some(広がり))
}

fn 書き出させる(
    種: マップ生成の乱数の種,
    ソースルート: Option<&ソースルート>,
    世界の広がり: Option<世界の広がり>,
) -> Result<String, 生成器エラー> {
    println!("[xtask] 場所巡りの世界のソースアセットを種{}から生成", 種.値());
    let 指定 = 生成の指定::ソースアセットを生成する {
        場所巡りの世界の種: Some(種),
        ソースルート,
        世界の広がり,
    };
    アセット生成器の起動::始める(&指定)?.走らせて標準出力を取り込む()
}
