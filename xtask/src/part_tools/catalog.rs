//! 部品のカタログを組み上げる入口。実体はアセットコンパイラの組み上げ器exampleであり、ここが担当するのは
//! 引数の受け渡しと終了コードの写しだけである。起こし方は`asset_generator`の器が持つ。
//!
//! `check-glb`と分けるのは、この検査がファイル1件では判定できないためである。対の相手がカタログに存在するかは、
//! 全件を読み終えて初めて答えが出る。
//! 参照: `_doc/設計/部品カタログと接合点.md`「カタログ横断の検査」

use std::process::ExitCode;

use crate::asset_generator::{アセット生成器の起動, 検査するファイル一覧, 生成の指定, 生成器エラー};

pub fn カタログを組み上げる(引数一覧: &[String]) -> ExitCode {
    match 組み上げ器を走らせる(引数一覧) {
        Ok(()) => ExitCode::SUCCESS,
        Err(理由) => {
            eprintln!("[xtask] 部品カタログを組み上げられない: {理由}");
            eprintln!("使い方: cargo xtask part-catalog <部品のglbまたはgltfのパス> ...");
            ExitCode::FAILURE
        }
    }
}

fn 組み上げ器を走らせる(引数一覧: &[String]) -> Result<(), 生成器エラー> {
    アセット生成器の起動::始める(&生成の指定::部品カタログを組み上げる {
        部品のファイル一覧: &検査するファイル一覧::コマンド行の語から生成する(引数一覧)?,
    })?
    .画面へ流したまま走らせて終わりを待つ()
}
