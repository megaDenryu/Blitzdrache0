//! 部品を組み立ててBlender側の正解表と突き合わせる入口。実体はアセットコンパイラの突き合わせ器exampleであり、
//! ここが担当するのは引数の受け渡しと終了コードの写しだけである。
//!
//! 正解表のパスを引数で受けるのは、正解表が外部のリポジトリにあり、置き場を本体のコードへ焼かないためである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「段2の完了条件」

use std::path::Path;
use std::process::ExitCode;

use crate::asset_generator::{アセット生成器の起動, 検査するファイル一覧, 生成の指定, 生成器エラー};

pub fn 組み立てを突き合わせる(引数一覧: &[String]) -> ExitCode {
    match 突き合わせ器を走らせる(引数一覧) {
        Ok(()) => ExitCode::SUCCESS,
        Err(理由) => {
            eprintln!("[xtask] 組み立ての突き合わせが不合格または失敗である: {理由}");
            eprintln!("使い方: cargo xtask part-assembly <組み立ての正解表のjson> <部品のglbまたはgltfのパス> ...");
            ExitCode::FAILURE
        }
    }
}

fn 突き合わせ器を走らせる(引数一覧: &[String]) -> Result<(), 生成器エラー> {
    let Some((正解表のパス, 部品のパス一覧)) = 引数一覧.split_first() else {
        return Err(生成器エラー::検査するファイルが1つも無い);
    };
    アセット生成器の起動::始める(&生成の指定::組み立てを正解表と突き合わせる {
        正解表のパス: Path::new(正解表のパス),
        部品のファイル一覧: &検査するファイル一覧::コマンド行の語から生成する(部品のパス一覧)?,
    })?
    .画面へ流したまま走らせて終わりを待つ()
}
