//! アプリの終了時報告から点光源の影の計器を取り出す工程。受け取るのは標準出力と影を落とす灯の件数、
//! 返すのは記録の内訳と立方体配列の確保量とGPU時間である。行の綴りは`crates/blitz_app/src/reports/point_light_shadow.rs`と
//! 同`crates/blitz_app/src/reports.rs`の出力と一致させている。
//!
//! GPU時間を`Option`で持つのは、影を落とす灯が0件のフレームがこのパスを1本も積まず、パス別GPU時間の表にこの区間が
//! 1行も出ないためである。無い行を0ミリ秒として読むと、「測っていない」と「測ったら0だった」が同じ値になる。

use crate::report_parse::section_parse::{区画の行, 区画の行一覧, 括弧に触れた鍵の次の小数, 鍵の次の整数};

const 記録内訳の見出し: &str = "点光源の影の記録内訳";
const メモリの見出し: &str = "Vulkanメモリ確保:";
const GPU時間の見出し: &str = "パス別GPU時間";
const 立方体配列の用途名: &str = "点光源の影の立方体配列:";
const 点光源の影の区間名: &str = "点光源の影:";

pub(super) struct 点光源の影の計器 {
    pub(super) 影を落とす灯の件数: usize,
    pub(super) 記録した面の数: u64,
    pub(super) 絞りが判定した発行数: u64,
    pub(super) 絞りを通った発行数: u64,
    pub(super) 描画の発行数: u64,
    pub(super) 立方体配列の確保バイト数: u64,
    /// 直近60フレームの窓のp50。影を落とす灯が0件のときは`None`である。
    pub(super) gpu時間のp50ms: Option<f64>,
}

pub(super) fn 点光源の影の計器を取り出す(
    標準出力: &str, 影を落とす灯の件数: usize
) -> Result<点光源の影の計器, String> {
    let 内訳 = 区画の行一覧(標準出力, 記録内訳の見出し)?;
    Ok(点光源の影の計器 {
        影を落とす灯の件数,
        記録した面の数: 内訳から整数を読む(&内訳, "点光源の影の記録した面の数:")?,
        絞りが判定した発行数: 内訳から整数を読む(&内訳, "点光源の影の絞りが判定した発行数:")?,
        絞りを通った発行数: 内訳から整数を読む(&内訳, "点光源の影の絞りを通った発行数:")?,
        描画の発行数: 内訳から整数を読む(&内訳, "点光源の影の描画発行数:")?,
        立方体配列の確保バイト数: 立方体配列の確保量を読む(標準出力)?,
        gpu時間のp50ms: 点光源の影のp50を読む(標準出力)?,
    })
}

fn 内訳から整数を読む(区画: &[&str], 鍵: &str) -> Result<u64, String> {
    鍵の次の整数(区画の行(区画, 鍵)?, 鍵)
}

fn 立方体配列の確保量を読む(標準出力: &str) -> Result<u64, String> {
    let 区画 = 区画の行一覧(標準出力, メモリの見出し)?;
    鍵の次の整数(区画の行(&区画, 立方体配列の用途名)?, 立方体配列の用途名)
}

/// パス別GPU時間の表に点光源の影の行があればそのp50を返す。表そのものが無い実行は`--report-gpu-times`を渡していないため、
/// 行の不在と表の不在を分けずにどちらも`None`にする。
fn 点光源の影のp50を読む(標準出力: &str) -> Result<Option<f64>, String> {
    let Ok(区画) = 区画の行一覧(標準出力, GPU時間の見出し) else {
        return Ok(None);
    };
    let Ok(行) = 区画の行(&区画, 点光源の影の区間名) else {
        return Ok(None);
    };
    括弧に触れた鍵の次の小数(行, "p50").map(Some)
}
