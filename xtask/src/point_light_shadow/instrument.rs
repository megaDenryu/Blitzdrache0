//! アプリの終了時報告から点光源の影の計器を取り出す工程。受け取るのは終了時報告と影を落とす灯の件数、
//! 返すのは記録の内訳と立方体配列の確保量とGPU時間である。行の綴りは`crates/blitz_app/src/reports/point_light_shadow.rs`と
//! 同`crates/blitz_app/src/reports.rs`の出力と一致させている。
//!
//! GPU時間を`Option`で持つのは、影を落とす灯が0件のフレームがこのパスを1本も積まず、パス別GPU時間の表にこの区間が
//! 1行も出ないためである。無い行を0ミリ秒として読むと、「測っていない」と「測ったら0だった」が同じ値になる。

use crate::acceptance::{報告の区画, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

const 記録内訳の見出し: 報告の見出し = 報告の見出し::定数から生成する("点光源の影の記録内訳");
const メモリの見出し: 報告の見出し = 報告の見出し::定数から生成する("Vulkanメモリ確保:");
const GPU時間の見出し: 報告の見出し = 報告の見出し::定数から生成する("パス別GPU時間");
const 立方体配列の用途名: &str = "点光源の影の立方体配列:";
const 点光源の影の区間名: &str = "点光源の影:";
/// 中央値の鍵。分布の行では開き括弧が鍵へ触れているため、末尾一致で探す。
const 中央値の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("p50");

pub(super) struct 点光源の影の計器 {
    pub(super) 影を落とす灯の件数: usize,
    pub(super) 記録した面の数: u64,
    pub(super) 絞りが判定した発行数: u64,
    pub(super) 絞りを通った発行数: u64,
    pub(super) 描画の発行数: u64,
    pub(super) 立方体配列の確保バイト数: u64,
    /// 直近60フレームの窓のp50。影を落とす灯が0件のときは`None`である。
    pub(super) gpu時間のp50ms: Option<f64>,
}

pub(super) fn 点光源の影の計器を取り出す(
    報告: &終了時報告,
    影を落とす灯の件数: usize,
) -> Result<点光源の影の計器, 検収エラー> {
    let 内訳 = 報告.見出しの区画(記録内訳の見出し)?;
    Ok(点光源の影の計器 {
        影を落とす灯の件数,
        記録した面の数: 区画から整数を読む(&内訳, "点光源の影の記録した面の数:")?,
        絞りが判定した発行数: 区画から整数を読む(&内訳, "点光源の影の絞りが判定した発行数:")?,
        絞りを通った発行数: 区画から整数を読む(&内訳, "点光源の影の絞りを通った発行数:")?,
        描画の発行数: 区画から整数を読む(&内訳, "点光源の影の描画発行数:")?,
        立方体配列の確保バイト数: 立方体配列の確保量を読む(報告)?,
        gpu時間のp50ms: 点光源の影のp50を読む(報告)?,
    })
}

/// 区画の中で鍵で始まる行を探し、その鍵に続く数を読む。行の頭に立つ鍵は接頭辞でもあるため、
/// 見出しとしての照合と鍵としての照合の両方に同じ綴りを使う。
fn 区画から整数を読む(区画: &報告の区画, 鍵の綴り: &'static str) -> Result<u64, 検収エラー> {
    区画
        .接頭辞の行(&報告の見出し::定数から生成する(鍵の綴り))?
        .鍵に結ばれた語から数字だけを読む(&報告の行の鍵::定数から生成する(鍵の綴り), 鍵に値が結ばれる形::次の語が値である)
}

fn 立方体配列の確保量を読む(報告: &終了時報告) -> Result<u64, 検収エラー> {
    区画から整数を読む(&報告.見出しの区画(メモリの見出し)?, 立方体配列の用途名)
}

/// パス別GPU時間の表に点光源の影の行があればそのp50を返す。表そのものが無い実行は`--report-gpu-times`を渡していないため、
/// 行の不在と表の不在を分けずにどちらも`None`にする。
fn 点光源の影のp50を読む(報告: &終了時報告) -> Result<Option<f64>, 検収エラー> {
    let Ok(区画) = 報告.見出しの区画(GPU時間の見出し) else {
        return Ok(None);
    };
    let Ok(行) = 区画.接頭辞の行(&報告の見出し::定数から生成する(点光源の影の区間名)) else {
        return Ok(None);
    };
    行.鍵に結ばれた数(&中央値の鍵, 鍵に値が結ばれる形::この綴りで終わる語の次が値である)
        .map(Some)
}
