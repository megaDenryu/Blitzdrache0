//! 読み戻し画像の矩形領域と、その中の平均輝度を採る工程。受け取るのは読み戻し画像と矩形、返すのは平均輝度である。
//! どの矩形が絵の何を写しているかは領域の正本(`interior_region`と`night_region`)が決め、ここは測るだけを担う。
//!
//! 矩形を画面の千分率で持つのは、読み戻し画像の寸法がウィンドウの大きさで変わるためである。千分率の整数で持つのは、
//! 小数から画素位置を出すと丸めの向きを別に決める必要が出るためであり、掛けてから割れば向きが1つに定まる。
//!
//! 平均輝度を3つの成分の相加平均で測るのは、`cargo xtask cluster-lights`の屋内の明るさと同じ測り方へ揃えるためである。
//! 明るいか暗いかを比べるだけの用途に重み付きの相対輝度を持ち込まない。
//!
//! 向きを綴りでなく枝で持つのは、横の千分率を縦の画面の長さで割る取り違えが、綴りの組では型を通ってしまうためである。

use crate::acceptance::{判定の名前, 判定の破れ, 画素の横位置, 画素の縦位置, 読み戻し画像};

pub(super) struct 画面の矩形 {
    pub(super) 横の千分率: (usize, usize),
    pub(super) 縦の千分率: (usize, usize),
}

#[derive(Clone, Copy)]
enum 辺の向き {
    横,
    縦,
}

impl 辺の向き {
    fn 綴り(self) -> &'static str {
        match self {
            Self::横 => "横",
            Self::縦 => "縦",
        }
    }

    /// この向きでの千分率の対と画面の長さ。両方を1つの枝から取ることで、横の千分率を縦の長さへ掛けられなくする。
    fn 千分率と画面の長さ(self, 矩形: &画面の矩形, 画像: &読み戻し画像) -> ((usize, usize), usize) {
        match self {
            Self::横 => (矩形.横の千分率, 画像.幅().画素数()),
            Self::縦 => (矩形.縦の千分率, 画像.高さ().画素数()),
        }
    }
}

pub(super) fn 矩形の平均輝度を採る(画像: &読み戻し画像, 矩形: &画面の矩形) -> Result<f64, 判定の破れ> {
    let (x開始, x終端) = 辺の画素範囲を求める(辺の向き::横, 矩形, 画像)?;
    let (y開始, y終端) = 辺の画素範囲を求める(辺の向き::縦, 矩形, 画像)?;
    let mut 合計 = 0.0;
    let mut 画素数 = 0_usize;
    for y in y開始..y終端 {
        for x in x開始..x終端 {
            let 画素 = 画像.座標の画素(画素の横位置::生成する(x), 画素の縦位置::生成する(y));
            合計 += (f64::from(画素[0]) + f64::from(画素[1]) + f64::from(画素[2])) / 3.0;
            画素数 += 1;
        }
    }
    Ok(合計 / 画素数を実数へ写す(画素数))
}

/// 千分率の対をこの向きの画素の範囲へ写し、範囲が空でなく読み戻し画像の内側にあることを課す。
fn 辺の画素範囲を求める(
    向き: 辺の向き, 矩形: &画面の矩形, 画像: &読み戻し画像
) -> Result<(usize, usize), 判定の破れ> {
    let ((始まりの千分率, 終わりの千分率), 画面の長さ) = 向き.千分率と画面の長さ(矩形, 画像);
    let 開始 = 千分率を画素へ写す(画面の長さ, 始まりの千分率);
    let 終端 = 千分率を画素へ写す(画面の長さ, 終わりの千分率);
    let 判定名 = 辺の終端の判定名(向き, 始まりの千分率, 終わりの千分率, 画像);
    判定名.下限を課す(終端, 開始 + 1)?;
    判定名.上限を課す(終端, 画面の長さ)?;
    Ok((開始, 終端))
}

/// 千分率を綴りへ入れるのは、どの領域の矩形が外れたのかを、領域の名前を運ばずに読み手が特定できるようにするためである。
fn 辺の終端の判定名(
    向き: 辺の向き, 始まりの千分率: usize, 終わりの千分率: usize, 画像: &読み戻し画像
) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "平均輝度を採る判定領域の{}の画素範囲の終端(千分率{始まりの千分率}から{終わりの千分率}・読み戻し画像は{})",
        向き.綴り(),
        画像.寸法の綴り()
    ))
}

fn 千分率を画素へ写す(長さ: usize, 千分率: usize) -> usize {
    長さ * 千分率 / 1000
}

fn 画素数を実数へ写す(値: usize) -> f64 {
    f64::from(u32::try_from(値).unwrap_or(u32::MAX))
}
