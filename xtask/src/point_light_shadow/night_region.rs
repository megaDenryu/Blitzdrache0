//! 夜の世界で判定する4つの領域の正本。担当するのは、どの矩形が絵の何を写しているかと、その領域がどの灯の影で
//! 暗くなるべきかの宣言である。判定の値と判定そのものは`night_judgment`が持つ。
//!
//! 影を落とす灯は中心から近い順に選ばれ、1件目が大域(46.25, 4.0, 46.25)、2件目が(53.75, 4.0, 46.25)に立つ
//! (正本: `crates/blitz_app/src/app/scene_lighting/night_lights/lamp_field.rs`)。1件目の傍らに細く高い角柱が、
//! 2件目の傍らに幅広く低い壁が立つ(正本: `crates/blitz_asset_compiler/examples/compile_assets/world/night_lights_declaration.rs`)。
//!
//! 4つの領域は、2つの灯の影の形が正反対であることを写す。角柱の影は南北に長く東西に狭く、壁の影は東西に広く南北に短い。
//! 1つの立方体では、南北に長い影と東西に広い影を同時に作れない。したがって「角柱の影の南北に長い先が暗く、東西の脇が明るい」ことと
//! 「壁の影の東西に広い端が暗く、南北の先が明るい」ことが同時に成り立つなら、2つの灯は別々の立方体を読んでいる。
//! 矩形は1280かける720の絵の差分を見て決めた。構図の正本は`crates/blitz_app/src/app/scene_camera/night_lights_view.rs`である。

use super::region::画面の矩形;

/// その領域がどの灯の影で暗くなるべきか。
pub(super) enum 夜の領域の期待 {
    /// 影を落とす1件目の灯(角柱の傍らの灯)が暗くする。2件目を足しても暗さは変わらない。
    影を落とす1件目の灯が暗くする,
    /// 影を落とす2件目の灯(壁の傍らの灯)が暗くする。1件目だけのときは明るいままである。
    影を落とす2件目の灯が暗くする,
    /// どちらの灯の影も届かない。影を落とす件数を振っても明るさが1つも動かない。
    どの灯の影も届かない,
}

