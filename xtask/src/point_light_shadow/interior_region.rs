//! 屋内の世界で判定する6つの領域の正本。担当するのは、どの矩形が絵の何を写しているかと、その領域が影の有無で
//! どう動くべきかの宣言である。判定の値と判定そのものは`interior_judgment`が持つ。
//!
//! 構図の正本は`crates/blitz_app/src/app/scene_camera/stone_hut_doorway_view.rs`である。カメラは戸口の正面に立ち、
//! 小屋の正面が画面をほぼ埋め、戸口の奥に屋内が見える。矩形はこの構図の1280かける720の絵を見て決めた。
//!
//! 壁の継ぎ目の漏光の線は遠近で斜めに走るため、矩形はその斜めの走りを縦の範囲ごと囲む。線の外の暗い壁も一緒に入るが、
//! 線が消えたかどうかは平均で十分に分かれる(制定時の実測で左は影なし31.00・影付き6.58)。
//!
//! 外側の4領域を壁の継ぎ目2つと左右の地面2つに取るのは、壁を抜けた漏光が絵に出る場所がこの4つだからである。
//! 外壁の面そのものは、灯と法線が逆を向いて拡散の項が0になるため、影の有無で1つも動かない。

use super::region::画面の矩形;

/// その領域が影の有無でどう動くべきか。
pub(super) enum 屋内の領域の期待 {
    /// 壁を抜けた灯の漏光がこの領域を明るくしており、影を入れると灯を消した対照と同じ暗さへ戻る。
    影で漏光が消える,
    /// 屋内にある灯がこの領域を直に照らしており、影を入れても明るさが変わらない。
    影の有無で変わらず灯が照らす,
    /// 戸口から出た灯がこの領域を照らしており、影を入れると戸口の枠が遮る縁のぶんだけ減る。
    影で縁のぶんだけ減る,
}

pub(super) struct 屋内の判定領域 {
    pub(super) 名前: &'static str,
    pub(super) 矩形: 画面の矩形,
    pub(super) 期待: 屋内の領域の期待,
}

