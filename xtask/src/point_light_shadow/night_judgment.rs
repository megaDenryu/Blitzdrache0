//! 夜の領域ごとの平均輝度に対する判定値と判定。受け取るのは領域ごとの3条件の平均輝度、返すのは合否である。
//! どの領域が何を写しているかと、その領域がどの灯の影で暗くなるべきかは`night_region`が宣言する。
//!
//! 判定値はすべて、この世界とこの構図と2つの遮蔽物という固定入力での実測から余白を持って制定した値である。
//! 遮蔽物の寸法か置き場所を変えたら測り直して制定し直す。
//! 参照: `_doc/設計/クラスタ多光源と点光源の影.md`「第5段階の検収の入口」

use super::night_measure::夜の領域ごとの平均輝度;
use super::night_region::{夜の判定領域の一覧, 夜の領域の期待};
use crate::acceptance::{判定の名前, 判定の破れ};

/// 2つの条件の平均輝度が一致すると認める差。制定時(2026-08-11)の実測は、暗くならないはずの2領域も、
/// 暗くするはずでない灯を足したときの領域も、小数点以下2桁まで完全に一致していた。
const 一致とみなす差の上限: f64 = 0.5;

/// 角柱の影が「南北に長い先」を暗くする量の下限。制定時の実測は7.41である。この領域は角柱の足元から南北に離れており、
/// 壁のように背の低い遮蔽物の影は届かない。下限をおよそ半分に置く。
const 角柱の影が暗くする量の下限: f64 = 4.0;

/// 壁の影が「東西に広い端」を暗くする量の下限。制定時の実測は23.36である。この領域は壁の東西の端にあり、
/// 角柱のように細い遮蔽物の影は届かない。下限をおよそ半分に置く。
const 壁の影が暗くする量の下限: f64 = 12.0;

const 夜の測りが並べた領域の数: 判定の名前 =
    判定の名前::定数から生成する("夜の測りが並べた領域の数(宣言した判定領域の数と一致するはず)");

pub(super) fn 夜の領域を判定する(領域一覧: &[夜の領域ごとの平均輝度]) -> Result<(), 判定の破れ> {
    夜の測りが並べた領域の数.一致を課す(領域一覧.len(), 夜の判定領域の一覧.len())?;
    for (領域, 宣言) in 領域一覧.iter().zip(夜の判定領域の一覧.iter()) {
        match 宣言.期待 {
            夜の領域の期待::影を落とす1件目の灯が暗くする => 一件目で暗くなったかを確かめる(領域)?,
            夜の領域の期待::影を落とす2件目の灯が暗くする => 二件目で暗くなったかを確かめる(領域)?,
            夜の領域の期待::どの灯の影も届かない => どの件数でも動かないかを確かめる(領域)?,
        }
    }
    Ok(())
}

fn 一件目で暗くなったかを確かめる(領域: &夜の領域ごとの平均輝度) -> Result<(), 判定の破れ> {
    暗くなる量が下限に届くかを確かめる(領域.名前, "影付き0件と1件", 領域.影付き0件, 領域.影付き1件, 角柱の影が暗くする量の下限)?;
    差が上限の内側かを確かめる(領域.名前, "影付き1件と2件", 領域.影付き1件, 領域.影付き2件)
}

fn 二件目で暗くなったかを確かめる(領域: &夜の領域ごとの平均輝度) -> Result<(), 判定の破れ> {
    差が上限の内側かを確かめる(領域.名前, "影付き0件と1件", 領域.影付き0件, 領域.影付き1件)?;
    暗くなる量が下限に届くかを確かめる(領域.名前, "影付き0件と2件", 領域.影付き0件, 領域.影付き2件, 壁の影が暗くする量の下限)
}

fn どの件数でも動かないかを確かめる(領域: &夜の領域ごとの平均輝度) -> Result<(), 判定の破れ> {
    差が上限の内側かを確かめる(領域.名前, "影付き0件と1件", 領域.影付き0件, 領域.影付き1件)?;
    差が上限の内側かを確かめる(領域.名前, "影付き0件と2件", 領域.影付き0件, 領域.影付き2件)
}

fn 差が上限の内側かを確かめる(領域名: &str, 対の名前: &str, 左: f64, 右: f64) -> Result<(), 判定の破れ> {
    二条件の差の判定名(領域名, 対の名前, "一致すべき").上限を課す((左 - 右).abs(), 一致とみなす差の上限)
}

fn 暗くなる量が下限に届くかを確かめる(
    領域名: &str,
    対の名前: &str,
    明るい側: f64,
    暗い側: f64,
    下限: f64,
) -> Result<(), 判定の破れ> {
    二条件の差の判定名(領域名, 対の名前, "後ろの条件で暗くなるべき").下限を課す(明るい側 - 暗い側, 下限)
}

fn 二条件の差の判定名(領域名: &str, 対の名前: &str, 期待の綴り: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{領域名}の{対の名前}の平均輝度の差({期待の綴り}対である)"))
}
