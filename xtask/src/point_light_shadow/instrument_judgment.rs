//! 点光源の影の計器に対する判定値と判定。受け取るのは1条件の計器、返すのは合否である。計器の取り出しは`instrument`が持つ。
//!
//! 立方体配列の確保量だけは実測からの余白を持たない完全一致で見る。灯の上限件数と面の数と面の一辺と
//! 深度1テクセルのバイト数の積は構図にも実行のたびの揺れにも依らず決まり、対象機ではこの積が実測の確保量と
//! ちょうど一致したため、24MiBという常駐量の予算をその値で固定した。1バイトでも動けば、確保の側か見積の側の
//! どちらかが動いている。
//! 注意: 読んでいるのは`VkMemoryRequirements::size`であり、機材ごとの配置の余白を含みうる。この完全一致は
//! 対象機での予算の固定であって、全機材で成り立つ恒等式ではない。別の機材で落ちたら、まず余白の有無を確かめる。
//!
//! GPU時間には判定を置かない。枠の制定は実測を読んで人が裁定する
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断h」)。

use super::instrument::点光源の影の計器;
use crate::acceptance::{判定の名前, 判定の破れ};

/// 立方体の面の数。正本は`crates/blitz_render/src/cube_image.rs`の`立方体の全面`である。値は立方体という形が決める。
const 立方体の面の数: u64 = 6;

/// 影を持てる灯の上限件数。正本は`crates/blitz_render/src/point_light_shadow/capacity.rs`であり、
/// xtaskが外部クレートへ依存しない方針のため値を持ち直している。この二重定義は`cargo xtask conform`の定数一致検査へ登録してある。
const 影を持てる灯の上限件数: u64 = 4;

/// 立方体の1つの面の一辺のテクセル数。正本は上限件数と同じファイルであり、二重定義の扱いも同じである。
const 点光源の影の面の一辺: u64 = 512;

/// 深度1テクセルのバイト数。立方体配列の形式はD32_SFLOATである(正本: `crates/blitz_render/src/vulkan/point_light_shadow_map/create/image.rs`)。
const テクセル1つのバイト数: u64 = 4;

const 期待する立方体配列の確保バイト数: u64 =
    影を持てる灯の上限件数 * 立方体の面の数 * 点光源の影の面の一辺 * 点光源の影の面の一辺 * テクセル1つのバイト数;

pub(super) fn 点光源の影の計器を判定する(計器: &点光源の影の計器) -> Result<(), 判定の破れ> {
    let 件数 = 計器.影を落とす灯の件数;
    立方体配列の確保バイト数の判定名(件数).一致を課す(計器.立方体配列の確保バイト数, 期待する立方体配列の確保バイト数)?;
    記録した面の数の判定名(件数).一致を課す(計器.記録した面の数, 立方体の面の数 * 件数)?;
    描画の発行数の判定名(件数).一致を課す(計器.描画の発行数, 計器.絞りを通った発行数)?;
    絞りが判定した発行数の判定名(件数).下限を課す(計器.絞りが判定した発行数, 計器.絞りを通った発行数)
}

/// 夜の世界だけが要求する判定。影を落とす灯の影響半径より小さい遮蔽物が2件あるため、面ごとの絞りは必ず何かを落とす。
/// 1件も落ちないなら、境界球の判定が全部を通しているか、絞りそのものが呼ばれていない。
pub(super) fn 夜の世界の絞りが落としたかを判定する(計器: &点光源の影の計器) -> Result<(), 判定の破れ> {
    let 件数 = 計器.影を落とす灯の件数;
    if 件数 == 0 {
        return Ok(());
    }
    夜の世界で絞りが判定した発行数の判定名(件数).下限を課す(計器.絞りが判定した発行数, 計器.絞りを通った発行数 + 1)
}

fn 立方体配列の確保バイト数の判定名(件数: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "影付き{件数}件での点光源の影の立方体配列の確保バイト数(期待は上限件数{影を持てる灯の上限件数}かける面{立方体の面の数}かける一辺{点光源の影の面の一辺}の二乗かける{テクセル1つのバイト数}バイト)"
    ))
}

fn 記録した面の数の判定名(件数: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(
        format!("影付き{件数}件で記録した点光源の影の面の数(期待は灯1件につき{立方体の面の数}面)"),
    )
}

fn 描画の発行数の判定名(件数: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "影付き{件数}件での点光源の影の描画の発行数(絞りを通った発行数と食い違うなら、記録の途中で発行が落ちているか数え損ねている)"
    ))
}

fn 絞りが判定した発行数の判定名(件数: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "影付き{件数}件で点光源の影の絞りが判定した発行数(通った発行数より少なくなることはない)"
    ))
}

fn 夜の世界で絞りが判定した発行数の判定名(件数: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "夜の世界の影付き{件数}件で面ごとの絞りが判定した発行数(通った発行数より多くなければ絞りが1件も落としていない)"
    ))
}
