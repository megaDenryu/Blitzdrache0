//! 点光源の影の計器に対する判定値と判定。受け取るのは1条件の計器、返すのは合否である。計器の取り出しは`instrument`が持つ。
//!
//! 立方体配列の確保量だけは実測からの余白を持たない完全一致で見る。この量は灯の上限件数と面の数と面の一辺と
//! 深度1テクセルのバイト数の積そのものであり、機材にも構図にも依らないためである。1バイトでも違えば、
//! 確保の側か見積の側のどちらかが壊れている。
//!
//! GPU時間には判定を置かない。枠の制定は実測を読んで人が裁定する
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「判断h」)。

use super::instrument::点光源の影の計器;

/// 立方体の面の数。正本は`crates/blitz_render/src/cube_image.rs`の`立方体の全面`である。値は立方体という形が決める。
const 立方体の面の数: u64 = 6;

/// 影を持てる灯の上限件数。正本は`crates/blitz_render/src/point_light_shadow/capacity.rs`であり、
/// xtaskが外部クレートへ依存しない方針のため値を持ち直している。この二重定義は`cargo xtask conform`の定数一致検査へ登録してある。
const 影を持てる灯の上限件数: u64 = 4;

/// 立方体の1つの面の一辺のテクセル数。正本は上限件数と同じファイルであり、二重定義の扱いも同じである。
const 点光源の影の面の一辺: u64 = 512;

/// 深度1テクセルのバイト数。立方体配列の形式はD32_SFLOATである(正本: `crates/blitz_render/src/vulkan/point_light_shadow_map/create/image.rs`)。
const テクセル1つのバイト数: u64 = 4;

const 期待する立方体配列の確保バイト数: u64 =
    影を持てる灯の上限件数 * 立方体の面の数 * 点光源の影の面の一辺 * 点光源の影の面の一辺 * テクセル1つのバイト数;

pub(super) fn 計器を判定する(計器: &点光源の影の計器) -> Result<(), String> {
    let 件数 = 計器.影を落とす灯の件数;
    if 計器.立方体配列の確保バイト数 != 期待する立方体配列の確保バイト数 {
        return Err(format!(
            "影付き{件数}件で立方体配列の確保量が{}バイトだった(期待は上限件数{影を持てる灯の上限件数}かける面{立方体の面の数}かける一辺{点光源の影の面の一辺}の二乗かける{テクセル1つのバイト数}バイトで{期待する立方体配列の確保バイト数}バイト)",
            計器.立方体配列の確保バイト数
        ));
    }
    let 期待する面の数 = 立方体の面の数 * u64::try_from(件数).map_err(|誤り| format!("影を落とす灯の件数をu64へ写せない: {誤り}"))?;
    if 計器.記録した面の数 != 期待する面の数 {
        return Err(format!(
            "影付き{件数}件で記録した面の数が{}だった(期待は灯1件につき{立方体の面の数}面で{期待する面の数})",
            計器.記録した面の数
        ));
    }
    if 計器.絞りを通った発行数 != 計器.描画の発行数 {
        return Err(format!(
            "影付き{件数}件で絞りを通った発行数{}と描画の発行数{}が食い違う(記録の途中で発行が落ちているか数え損ねている)",
            計器.絞りを通った発行数, 計器.描画の発行数
        ));
    }
    if 計器.絞りが判定した発行数 < 計器.絞りを通った発行数 {
        return Err(format!(
            "影付き{件数}件で絞りが判定した発行数{}が通った発行数{}より少ない",
            計器.絞りが判定した発行数, 計器.絞りを通った発行数
        ));
    }
    Ok(())
}

/// 夜の世界だけが要求する判定。影を落とす灯の影響半径より小さい遮蔽物が2件あるため、面ごとの絞りは必ず何かを落とす。
/// 1件も落ちないなら、境界球の判定が全部を通しているか、絞りそのものが呼ばれていない。
pub(super) fn 夜の絞りが落としたかを判定する(計器: &点光源の影の計器) -> Result<(), String> {
    if 計器.影を落とす灯の件数 == 0 || 計器.絞りが判定した発行数 > 計器.絞りを通った発行数 {
        return Ok(());
    }
    Err(format!(
        "夜の世界の影付き{}件で面ごとの絞りが1件も落としていない(判定{}・通過{})",
        計器.影を落とす灯の件数, 計器.絞りが判定した発行数, 計器.絞りを通った発行数
    ))
}
