//! 屋内の領域ごとの平均輝度に対する判定値と判定。受け取るのは領域ごとの3条件の平均輝度、返すのは合否である。
//! どの領域が何を写しているかと、その領域が影の有無でどう動くべきかは`interior_region`が宣言する。
//!
//! 判定値はすべて、この2つの世界とこの構図という固定入力での実測から余白を持って制定した値である。
//! 影の品質の契約でも立方体影という方式の一般的な性質でもない。構図か灯の並びを変えたら測り直して制定し直す。
//! 参照: `_doc/設計/クラスタ多光源と点光源の影.md`「第5段階の検収の入口」

use super::interior_measure::屋内の領域ごとの平均輝度;
use super::interior_region::{屋内の判定領域の一覧, 屋内の領域の期待};
use crate::acceptance::{判定の名前, 判定の破れ};

/// 2つの条件の平均輝度が一致すると認める差。制定時(2026-08-11)の実測は、外側の4領域も戸口の内側の壁も
/// 小数点以下2桁まで完全に一致していた。0でなく0.5を置くのは、起動をまたいだ読み戻しが下位の数符号値だけ動きうるためである
/// (同一起動の中でのバイト一致だけが契約であり、それは`cargo xtask cluster-lights`が別に見る)。
const 一致とみなす差の上限: f64 = 0.5;

/// 影を入れたときに漏光が減る量の下限。制定時の実測は左の継ぎ目24.42・右の継ぎ目17.84・左の地面26.07・右の地面25.16であり、
/// この下限はその最小のおよそ半分である。影が1件も効かなくなれば差は0へ落ちるため、この位置で十分に分かれる。
const 漏光が減る量の下限: f64 = 8.0;

/// 灯が照らしている領域が対照より明るい量の下限。制定時の実測は戸口の内側の壁が179.94・戸口の手前の地面が72.74である。
const 灯が照らす量の下限: f64 = 40.0;

/// 戸口の手前の地面が影で減る量の範囲。制定時の実測は1.23である。下限を置くのは戸口の枠が縁を遮ることの反証であり、
/// 上限を置くのは、戸口から出る光そのものが遮られたら影が漏れていることの反証になるためである。
const 戸口の手前の地面が減る量の下限: f64 = 0.2;
const 戸口の手前の地面が減る量の上限: f64 = 8.0;

const 屋内の測りが並べた領域の数: 判定の名前 =
    判定の名前::定数から生成する("屋内の測りが並べた領域の数(宣言した判定領域の数と一致するはず)");

pub(super) fn 屋内の領域を判定する(領域一覧: &[屋内の領域ごとの平均輝度]) -> Result<(), 判定の破れ> {
    屋内の測りが並べた領域の数.一致を課す(領域一覧.len(), 屋内の判定領域の一覧.len())?;
    for (領域, 宣言) in 領域一覧.iter().zip(屋内の判定領域の一覧.iter()) {
        match 宣言.期待 {
            屋内の領域の期待::影で漏光が消える => 漏光が消えたかを確かめる(領域)?,
            屋内の領域の期待::影の有無で変わらず灯が照らす => 影の有無で変わらないかを確かめる(領域)?,
            屋内の領域の期待::影で縁のぶんだけ減る => 縁のぶんだけ減ったかを確かめる(領域)?,
        }
    }
    Ok(())
}

fn 漏光が消えたかを確かめる(領域: &屋内の領域ごとの平均輝度) -> Result<(), 判定の破れ> {
    差が上限の内側かを確かめる(領域.名前, "影付き3件と灯を消した対照", 領域.影付き3件, 領域.灯を消した対照)?;
    差が下限に届くかを確かめる(領域.名前, "影なしと灯を消した対照", 領域.影なし, 領域.灯を消した対照, 漏光が減る量の下限)
}

fn 影の有無で変わらないかを確かめる(領域: &屋内の領域ごとの平均輝度) -> Result<(), 判定の破れ> {
    差が上限の内側かを確かめる(領域.名前, "影付き3件と影なし", 領域.影付き3件, 領域.影なし)?;
    差が下限に届くかを確かめる(
        領域.名前,
        "影付き3件と灯を消した対照",
        領域.影付き3件,
        領域.灯を消した対照,
        灯が照らす量の下限,
    )
}

fn 縁のぶんだけ減ったかを確かめる(領域: &屋内の領域ごとの平均輝度) -> Result<(), 判定の破れ> {
    影で減った量の判定名(領域.名前).許容の範囲を課す(
        領域.影なし - 領域.影付き3件,
        戸口の手前の地面が減る量の下限,
        戸口の手前の地面が減る量の上限,
    )?;
    差が下限に届くかを確かめる(
        領域.名前,
        "影付き3件と灯を消した対照",
        領域.影付き3件,
        領域.灯を消した対照,
        灯が照らす量の下限,
    )
}

fn 差が上限の内側かを確かめる(領域名: &str, 対の名前: &str, 左: f64, 右: f64) -> Result<(), 判定の破れ> {
    二条件の差の判定名(領域名, 対の名前, "一致すべき").上限を課す((左 - 右).abs(), 一致とみなす差の上限)
}

fn 差が下限に届くかを確かめる(
    領域名: &str, 対の名前: &str, 明るい側: f64, 暗い側: f64, 下限: f64
) -> Result<(), 判定の破れ> {
    二条件の差の判定名(領域名, 対の名前, "明るい側が上回るべき").下限を課す(明るい側 - 暗い側, 下限)
}

fn 二条件の差の判定名(領域名: &str, 対の名前: &str, 期待の綴り: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{領域名}の{対の名前}の平均輝度の差({期待の綴り}対である)"))
}

fn 影で減った量の判定名(領域名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{領域名}が影付き3件で影なしより減った平均輝度(戸口の枠が縁を遮るぶんだけ減り、戸口から出る光そのものは遮られない)"
    ))
}
