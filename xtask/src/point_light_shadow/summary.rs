//! 測った値を表と要約の1行へ綴る工程。受け取るのは屋内と夜の領域の測りと件数ごとの計器と絵のパス、
//! 返すのは要約の文字列である。判定はこの工程が行わない。判定は入口が持ち、ここは読める形に並べるだけである。

use std::path::Path;

use super::instrument::点光源の影の計器;
use super::interior_measure::屋内の領域ごとの平均輝度;
use super::night_measure::夜の領域ごとの平均輝度;

pub(super) fn 屋内の領域の表を表示する(領域一覧: &[屋内の領域ごとの平均輝度]) {
    println!("屋内の領域ごとの平均輝度:");
    println!("  {:<26} | 影付き3件 | 影なし | 灯を消した対照", "領域");
    for 領域 in 領域一覧 {
        println!(
            "  {:<26} | {:>9.2} | {:>6.2} | {:>14.2}",
            領域.名前, 領域.影付き3件, 領域.影なし, 領域.灯を消した対照
        );
    }
}

pub(super) fn 夜の領域の表を表示する(領域一覧: &[夜の領域ごとの平均輝度]) {
    println!("夜の領域ごとの平均輝度:");
    println!("  {:<24} | 影付き0件 | 影付き1件 | 影付き2件", "領域");
    for 領域 in 領域一覧 {
        println!(
            "  {:<24} | {:>9.2} | {:>9.2} | {:>9.2}",
            領域.名前, 領域.影付き0件, 領域.影付き1件, 領域.影付き2件
        );
    }
}

pub(super) fn 点光源の影の計器の表を表示する(計器一覧: &[点光源の影の計器]) {
    println!("屋内で影付きの件数を振ったときの計器:");
    println!("  影付き件数 | 記録した面の数 | 絞りの判定数 | 絞りの通過数 | 描画発行数 | 立方体配列のバイト数 | GPU時間p50ms");
    for 計器 in 計器一覧 {
        let gpu時間 = 計器.gpu時間のp50ms.map_or_else(|| "パス無し".to_string(), |値| format!("{値:.4}"));
        println!(
            "  {:>10} | {:>14} | {:>12} | {:>12} | {:>10} | {:>20} | {:>12}",
            計器.影を落とす灯の件数,
            計器.記録した面の数,
            計器.絞りが判定した発行数,
            計器.絞りを通った発行数,
            計器.描画の発行数,
            計器.立方体配列の確保バイト数,
            gpu時間
        );
    }
}

pub(super) fn 検収の要約を組む(夜の計器: &点光源の影の計器, 絵一覧: &[&Path]) -> String {
    let 絵の並び = 絵一覧.iter().map(|絵| 絵.display().to_string()).collect::<Vec<String>>().join("と");
    format!(
        "屋内の6領域と夜の4領域を判定し、影付きの件数を0から3まで振った。夜の影付き2件は絞りの判定{}・通過{}で{}件を落とした。立方体配列は{}バイトである。絵は{絵の並び}",
        夜の計器.絞りが判定した発行数,
        夜の計器.絞りを通った発行数,
        夜の計器.絞りが判定した発行数 - 夜の計器.絞りを通った発行数,
        夜の計器.立方体配列の確保バイト数
    )
}
