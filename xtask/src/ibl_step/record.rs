//! 境界ごと領域ごとの生値の書き出しと、人が読む表の表示。受け取るのは1行ぶんの値または全領域の集計、返すものは無い。
//!
//! 生値を残すのは、上限の制定を後から別の切り口で読み直すためである。標準出力の表は領域ごとに1行へ畳むが、
//! どの境界でどれだけ動いたかの並びは畳む前の値にしかない。

use std::path::Path;

use super::summary::{分布, 領域の集計};

pub(super) struct 生値の行<'名前> {
    pub(super) 境界の上側の区間識別: u16,
    pub(super) 境界の天頂余弦: f64,
    pub(super) 最初に跨いだ一日内秒: f64,
    pub(super) 領域名: &'名前 str,
    pub(super) 画素数: usize,
    pub(super) 測れなかった画素数: u64,
}

pub(super) fn 見出し() -> String {
    "上側の区間識別\t境界の天頂余弦\t一日内秒\t領域\t画素数\t測れなかった画素数\t明るさの最大EV\t明るさのp95EV\t色の最大EV\t色のp95EV\n".to_string()
}

pub(super) fn 行にする(行: &生値の行<'_>, 明るさ: &分布, 色: &分布) -> String {
    format!(
        "{}\t{:.9}\t{:.6}\t{}\t{}\t{}\t{:.9}\t{:.9}\t{:.9}\t{:.9}\n",
        行.境界の上側の区間識別,
        行.境界の天頂余弦,
        行.最初に跨いだ一日内秒,
        行.領域名,
        行.画素数,
        行.測れなかった画素数,
        明るさ.最大,
        明るさ.p95,
        色.最大,
        色.p95
    )
}

pub(super) fn 生値を書く(書き先: &Path, 本文: &str) -> Result<(), String> {
    std::fs::write(書き先, 本文).map_err(|誤り| format!("{}を書けなかった: {誤り}", 書き先.display()))
}

pub(super) fn 表を表示する(集計一覧: &[領域の集計]) {
    println!("領域\t画素数\t明るさ最大EV\tその境界\t明るさp95最大EV\tその境界\t色最大EV\tその境界\t色p95最大EV\tその境界\t測れなかった画素");
    for 集計 in 集計一覧 {
        println!(
            "{}\t{}\t{:.6}\t{}\t{:.6}\t{}\t{:.6}\t{}\t{:.6}\t{}\t{}",
            集計.名前,
            集計.画素数,
            集計.明るさの最大.値,
            集計.明るさの最大.境界の上側の区間識別,
            集計.明るさのp95の最大.値,
            集計.明るさのp95の最大.境界の上側の区間識別,
            集計.色の最大.値,
            集計.色の最大.境界の上側の区間識別,
            集計.色のp95の最大.値,
            集計.色のp95の最大.境界の上側の区間識別,
            集計.測れなかった画素数
        );
    }
}

/// 入口の1行の要約。全領域の中で最も大きい明るさの段差と、それが出た領域と境界を出す。
pub(super) fn 要約を組む(集計一覧: &[領域の集計], 境界数: usize, 出力先: &Path) -> String {
    let 最大 = 集計一覧.iter().max_by(|左, 右| 左.明るさの最大.値.total_cmp(&右.明るさの最大.値));
    let 見出し = 最大.map_or_else(
        || "領域が1つも無い".to_string(),
        |集計| {
            format!(
                "最大の明るさの段差は{}の{:.4}EV(境界の上側の区間識別{})",
                集計.名前, 集計.明るさの最大.値, 集計.明るさの最大.境界の上側の区間識別
            )
        },
    );
    format!("境界{境界数}本を走査、{見出し}。領域別の表と生値は{}にある", 出力先.display())
}
