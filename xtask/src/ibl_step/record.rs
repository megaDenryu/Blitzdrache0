//! 跨ぎごと領域ごとの生値の書き出しと、人が読む表の表示。受け取るのは1行ぶんの値または全領域の集計、返すものは無い。
//!
//! 生値を残すのは、上限の制定を後から別の切り口で読み直すためである。標準出力の表は領域ごとに1行へ畳むが、
//! どの跨ぎでどれだけ動いたかの並びは畳む前の値にしかない。

use std::path::Path;

use super::crossing::跨ぎ;
use super::error::間引きの段差の計測エラー;
use super::summary::{分布, 最大の記録, 領域の集計};

pub(super) struct 生値の行<'材料> {
    pub(super) 跨ぎ: &'材料 跨ぎ,
    pub(super) 領域名: &'材料 str,
    pub(super) 画素数: usize,
    pub(super) 測れなかった画素数: u64,
}

pub(super) fn 見出し() -> String {
    "上側の区間識別\t方向\t境界の天頂余弦\t一日内秒\t領域\t画素数\t測れなかった画素数\t明るさの最大EV\t明るさのp95EV\t色の最大EV\t色のp95EV\n"
        .to_string()
}

pub(super) fn 行にする(行: &生値の行<'_>, 明るさ: &分布, 色: &分布) -> String {
    format!(
        "{}\t{}\t{:.9}\t{:.6}\t{}\t{}\t{}\t{:.9}\t{:.9}\t{:.9}\t{:.9}\n",
        行.跨ぎ.上側の区間識別,
        行.跨ぎ.方向,
        行.跨ぎ.境界の天頂余弦,
        行.跨ぎ.一日内秒,
        行.領域名,
        行.画素数,
        行.測れなかった画素数,
        明るさ.最大,
        明るさ.p95,
        色.最大,
        色.p95
    )
}

pub(super) fn 生値を書く(書き先: &Path, 本文: &str) -> Result<(), 間引きの段差の計測エラー> {
    std::fs::write(書き先, 本文).map_err(|誤り| 間引きの段差の計測エラー::生値を書けなかった {
        パス: 書き先.to_path_buf(),
        誤り,
    })
}

pub(super) fn 表を表示する(集計一覧: &[領域の集計], 跨ぎ一覧: &[跨ぎ]) {
    println!("領域\t画素数\t明るさ最大EV\tその跨ぎ\t明るさp95最大EV\tその跨ぎ\t色最大EV\tその跨ぎ\t色p95最大EV\tその跨ぎ\t測れなかった画素");
    for 集計 in 集計一覧 {
        println!(
            "{}\t{}\t{:.6}\t{}\t{:.6}\t{}\t{:.6}\t{}\t{:.6}\t{}\t{}",
            集計.名前,
            集計.画素数,
            集計.明るさの最大.値,
            跨ぎの名前(跨ぎ一覧, &集計.明るさの最大),
            集計.明るさのp95の最大.値,
            跨ぎの名前(跨ぎ一覧, &集計.明るさのp95の最大),
            集計.色の最大.値,
            跨ぎの名前(跨ぎ一覧, &集計.色の最大),
            集計.色のp95の最大.値,
            跨ぎの名前(跨ぎ一覧, &集計.色のp95の最大),
            集計.測れなかった画素数
        );
    }
}

/// 跨ぎを人が読む1語で表す。区間識別だけでは上りと下りを区別できないため、向きの語を必ず添える。
fn 跨ぎの名前(跨ぎ一覧: &[跨ぎ], 記録: &最大の記録) -> String {
    跨ぎ一覧.get(記録.跨ぎ番号).map_or_else(
        || format!("番号{}(一覧の外)", 記録.跨ぎ番号),
        |跨ぎ| format!("{}{}", 跨ぎ.上側の区間識別, 跨ぎ.方向),
    )
}

/// 入口の1行の要約。全領域の中で最も大きい明るさの段差と、それが出た領域と跨ぎを出す。
pub(super) fn 要約を組む(集計一覧: &[領域の集計], 跨ぎ一覧: &[跨ぎ], 出力先: &Path) -> String {
    let 最大 = 集計一覧.iter().max_by(|左, 右| 左.明るさの最大.値.total_cmp(&右.明るさの最大.値));
    let 見出し = 最大.map_or_else(
        || "領域が1つも無い".to_string(),
        |集計| {
            format!(
                "最大の明るさの段差は{}の{:.4}EV(跨ぎ{})",
                集計.名前,
                集計.明るさの最大.値,
                跨ぎの名前(跨ぎ一覧, &集計.明るさの最大)
            )
        },
    );
    format!("跨ぎ{}件を走査、{見出し}。領域別の表と生値は{}にある", 跨ぎ一覧.len(), 出力先.display())
}
