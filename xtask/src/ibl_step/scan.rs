//! 一日ぶんの走査。受け取るのは跨ぎの一覧と固定領域の一覧と撮影のベース名、返すのは領域ごとの集計と
//! 生値の本文と、代表点を選ぶための地面の段差の降順である。
//!
//! 段取りの入口から分けるのは、こちらが「束に切って撮り、測り、捨てる」ことだけを担い、領域マスクの撮り方も
//! 判定の中身も絵の選び方も知らないためである。
//!
//! 束に切るのは、1撮影の圧縮前HDRが1枚十数メガバイトあり、一日ぶんを残したままにすると数十ギガバイトを
//! 占めるためである。1束を測り終えるたびに生の画像を捨てるため、途中の占有は1束ぶんに収まる。

use std::path::Path;

use super::crossing::跨ぎ;
use super::summary::領域の集計;
use super::{measure, record, run};
use crate::sample_world_region::固定領域;

/// 1回の起動で撮る跨ぎの件数。1件が対の2枚で約30メガバイトを占めるため、1束の生の画像は約0.6ギガバイトに収まる。
const 一束の跨ぎ件数: usize = 20;

/// 地面の拡散の領域の並び順。固定領域一覧の先頭である。
pub(super) const 地面の領域番号: usize = 0;

pub(super) struct 走査の結果 {
    pub(super) 集計一覧: Vec<領域の集計>,
    pub(super) 生値: String,
    /// 跨ぎ番号と地面の明るさのp95の組を、値の降順に並べたもの。代表点を順位で選ぶのに使う。
    pub(super) 地面の段差の降順: Vec<(usize, f64)>,
}

pub(super) fn 走査する(跨ぎ一覧: &[跨ぎ], 領域一覧: &[固定領域], ベース名: &Path) -> Result<走査の結果, String> {
    let mut 結果 = 走査の結果 {
        集計一覧: 領域一覧.iter().map(|領域| 領域の集計::新規(領域.名前.clone(), 画素数(領域))).collect(),
        生値: record::見出し(),
        地面の段差の降順: Vec::with_capacity(跨ぎ一覧.len()),
    };
    for 束の先頭 in (0..跨ぎ一覧.len()).step_by(一束の跨ぎ件数) {
        let 件数 = 一束の跨ぎ件数.min(跨ぎ一覧.len() - 束の先頭);
        run::撮る(
            &run::撮るもの::範囲の段差 {
                最初の跨ぎ番号: 束の先頭,
                跨ぎの件数: 件数,
            },
            ベース名,
        )?;
        for (番号, 跨ぎ) in 跨ぎ一覧.iter().enumerate().skip(束の先頭).take(件数) {
            一件を測る(&mut 結果, (番号, 跨ぎ), 領域一覧, ベース名)?;
            run::撮影を捨てる(ベース名, 跨ぎ.上側の区間識別, &跨ぎ.方向);
        }
    }
    結果.地面の段差の降順.sort_by(|左, 右| 右.1.total_cmp(&左.1));
    Ok(結果)
}

fn 一件を測る(結果: &mut 走査の結果, 対象: (usize, &跨ぎ), 領域一覧: &[固定領域], ベース名: &Path) -> Result<(), String> {
    let (番号, 跨ぎ) = 対象;
    let 領域ごとのp95 = measure::跨ぎを測る(
        &measure::測る材料 {
            跨ぎ,
            跨ぎ番号: 番号,
            領域一覧,
            ベース名,
        },
        &mut 結果.集計一覧,
        &mut 結果.生値,
    )?;
    let 地面のp95 = 領域ごとのp95
        .get(地面の領域番号)
        .copied()
        .ok_or_else(|| "地面の領域の段差が測れなかった".to_string())?;
    結果.地面の段差の降順.push((番号, 地面のp95));
    Ok(())
}

fn 画素数(領域: &固定領域) -> u64 {
    u64::try_from(領域.画素添字一覧.len()).unwrap_or(u64::MAX)
}
