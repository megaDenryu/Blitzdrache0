//! 1つの跨ぎの対を測る工程。受け取るのは跨ぎとその番号と固定領域の一覧と撮影のベース名、
//! 返すのは領域ごとの集計への取り込みと生値の行の追記である。
//!
//! 走査の段取りから分けるのは、こちらが「対の2枚をどう読み比べるか」だけを担い、束をどう切って撮るかも、
//! 一日で何件走るかも知らないためである。

use super::crossing::跨ぎ;
use super::summary::領域の集計;
use super::{difference, record, run, summary};
use crate::acceptance::{圧縮前のHDR画像, 描画検収の実行環境};
use crate::sample_world_region::固定領域;

/// 1つの跨ぎを測るのに要る材料。引数の列が伸び続けるのを避けて1つに束ねる。
pub(super) struct 測る材料<'材料> {
    pub(super) 実行環境: &'材料 描画検収の実行環境,
    pub(super) 跨ぎ: &'材料 跨ぎ,
    pub(super) 跨ぎ番号: usize,
    pub(super) 領域一覧: &'材料 [固定領域],
}

/// 測った結果を集計と生値へ積み、領域ごとの明るさのp95を並びのまま返す。返すのは、代表点を順位で選ぶ側が
/// 跨ぎごとの値を要るためである。集計は全跨ぎの最大しか持たないため、跨ぎごとの値はここでしか取れない。
pub(super) fn 跨ぎを測る(材料: &測る材料<'_>, 集計一覧: &mut [領域の集計], 生値: &mut String) -> Result<Vec<f64>, String> {
    let (下側, 上側) = (一枚を読む(材料, "low")?, 一枚を読む(材料, "high")?);
    if !下側.寸法が同じか(&上側) {
        return Err(format!("対の2枚の寸法が違う: {}と{}", 下側.寸法の綴り(), 上側.寸法の綴り()));
    }
    let mut 明るさのp95一覧 = Vec::with_capacity(材料.領域一覧.len());
    for (領域, 集計) in 材料.領域一覧.iter().zip(集計一覧) {
        画素の並びが合うか(&下側, 領域)?;
        let mut 段差 = difference::領域の段差を求める(&下側, &上側, 領域);
        let 明るさ = summary::分布を採る(&mut 段差.明るさのev一覧)?;
        let 色 = summary::分布を採る(&mut 段差.色のev一覧)?;
        集計.取り込む(材料.跨ぎ番号, &明るさ, &色, 段差.測れなかった画素数);
        生値.push_str(&record::行にする(
            &record::生値の行 {
                跨ぎ: 材料.跨ぎ,
                領域名: &領域.名前,
                画素数: 領域.画素添字一覧.len(),
                測れなかった画素数: 段差.測れなかった画素数,
            },
            &明るさ,
            &色,
        ));
        明るさのp95一覧.push(明るさ.p95);
    }
    Ok(明るさのp95一覧)
}

fn 一枚を読む(材料: &測る材料<'_>, 側: &str) -> Result<圧縮前のHDR画像, String> {
    let 実行名 = run::撮影1枚の実行名(run::撮影の実行名, 材料.跨ぎ.上側の区間識別, &材料.跨ぎ.方向, 側)?;
    Ok(材料.実行環境.同じ置き場の圧縮前の画素を読み戻す(実行名)?)
}

/// 領域マスクと撮影の画素数が違えば、同じ添字が別の場所を指す。段差を測る前に落とす。
fn 画素の並びが合うか(画像: &圧縮前のHDR画像, 領域: &固定領域) -> Result<(), String> {
    match 領域.画素添字一覧.iter().max() {
        Some(最大) if *最大 >= 画像.画素数() => {
            Err(format!("領域「{}」の画素添字{最大}が撮影の画素数{}の外にある", 領域.名前, 画像.画素数()))
        }
        _ => Ok(()),
    }
}
