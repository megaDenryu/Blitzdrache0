//! 1つの境界の対を測る工程。受け取るのは境界と固定領域の一覧と撮影のベース名、
//! 返すのは領域ごとの集計への取り込みと生値の行の追記である。
//!
//! 走査の段取りから分けるのは、こちらが「対の2枚をどう読み比べるか」だけを担い、束をどう切って撮るかも、
//! 一日で何本走るかも知らないためである。

use std::path::Path;

use super::boundary::境界;
use super::summary::領域の集計;
use super::{difference, hdr_image, record, run, summary};
use crate::sample_world_region::固定領域;

pub(super) fn 境界を測る(
    境界: &境界,
    領域一覧: &[固定領域],
    集計一覧: &mut [領域の集計],
    生値: &mut String,
    ベース名: &Path,
) -> Result<(), String> {
    let 下側 = hdr_image::読み込む(&run::撮影のベース名(ベース名, 境界.上側の区間識別, "low"))?;
    let 上側 = hdr_image::読み込む(&run::撮影のベース名(ベース名, 境界.上側の区間識別, "high"))?;
    下側.寸法が合うか(&上側)?;
    for (領域, 集計) in 領域一覧.iter().zip(集計一覧) {
        画素の並びが合うか(&下側, 領域)?;
        let mut 段差 = difference::領域の段差を求める(&下側, &上側, 領域);
        let 明るさ = summary::分布を採る(&mut 段差.明るさのev一覧)?;
        let 色 = summary::分布を採る(&mut 段差.色のev一覧)?;
        集計.取り込む(境界.上側の区間識別, &明るさ, &色, 段差.測れなかった画素数);
        生値.push_str(&record::行にする(
            &record::生値の行 {
                境界の上側の区間識別: 境界.上側の区間識別,
                境界の天頂余弦: 境界.境界の天頂余弦,
                最初に跨いだ一日内秒: 境界.最初に跨いだ一日内秒,
                領域名: &領域.名前,
                画素数: 領域.画素添字一覧.len(),
                測れなかった画素数: 段差.測れなかった画素数,
            },
            &明るさ,
            &色,
        ));
    }
    Ok(())
}

/// 領域マスクと撮影の画素数が違えば、同じ添字が別の場所を指す。段差を測る前に落とす。
fn 画素の並びが合うか(画像: &hdr_image::HDR画像, 領域: &固定領域) -> Result<(), String> {
    match 領域.画素添字一覧.iter().max() {
        Some(最大) if *最大 >= 画像.画素数() => {
            Err(format!("領域「{}」の画素添字{最大}が撮影の画素数{}の外にある", 領域.名前, 画像.画素数()))
        }
        _ => Ok(()),
    }
}
