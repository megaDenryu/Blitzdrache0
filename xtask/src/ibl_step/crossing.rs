//! 一日の跨ぎの一覧の取り込み。受け取るものは無く、返すのは跨ぎごとの識別と向きと天頂余弦と時刻である。
//!
//! 一覧を自分で導かずblitz_appの報告を読むのは、跨ぎが刻みの設定と球面天文学から決まり、その両方の正本が
//! blitz_engineにあるためである。xtaskは外部クレートへ依存しない方針であり、写した表を持てば刻みを変えた
//! 実行と検収が別の跨ぎを見る。
//!
//! 読めない行を飛ばさずに落とすのは、1行の形式が変わっただけで検収が黙って少ない件数を測り、
//! 成功として終わってしまうためである。見出しが言う総数との一致と、番号が0からの連番であることも合わせて見る。

#[cfg(test)]
mod parse_tests;

mod parse;

use crate::acceptance::{アプリの起こし方, 世界を読まずに報告を採る実行環境, 検収の実行名, 検収エラー};

pub(super) use parse::跨ぎ;

/// この実行を指す名前。絵は書き出さないが、失敗の文面がどの実行かを名指すために要る。
const 跨ぎの報告の実行名: 検収の実行名 = 検収の実行名::定数から生成する("sun_zenith_crossings");

pub(super) fn 一覧を読む() -> Result<Vec<跨ぎ>, 検収エラー> {
    let 実行環境 = 世界を読まずに報告を採る実行環境::作る(アプリの起こし方::毎回cargoに構築させ構築の知らせを伏せて起動する);
    let 報告 = 実行環境.報告を採る(跨ぎの報告の実行名, &["--report-sun-zenith-crossings"])?;
    parse::一覧を読む(&報告)
}
