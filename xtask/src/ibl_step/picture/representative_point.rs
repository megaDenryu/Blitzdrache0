//! 絵に残す代表点の選び方。受け取るのは領域ごとの集計と地面の段差の順位、返すのは4つの代表点である。
//!
//! 選ぶ点を段差の閾値でなく順位で決めるのは、閾値を置くとこの入口が判定値を持ってしまうためである。

use super::super::scan::地面の領域番号;
use super::super::summary::領域の集計;
use crate::acceptance::{判定の名前, 判定の破れ};

/// 鏡の金属の領域の並び順。地面の次が金属の粗さの昇順であるため、その次が粗さ0の球である。
const 鏡の金属の領域番号: usize = 1;

/// 順位で選んだ代表点。呼び名はファイル名に使うためASCIIで持つ。
pub(super) struct 代表点 {
    pub(super) 呼び名: &'static str,
    pub(super) 跨ぎ番号: usize,
}

/// 代表点は4つである。地面の段差が最大の跨ぎ、鏡の金属の段差が最大の跨ぎ、地面の段差の順位が上から1割の跨ぎ
/// (帯の端に当たる)、地面の段差が最小の跨ぎ(帯の外)である。
pub(super) fn 代表点を選ぶ(
    集計一覧: &[領域の集計], 地面の段差の降順: &[(usize, f64)]
) -> Result<Vec<代表点>, 判定の破れ> {
    Ok(vec![
        代表点 {
            呼び名: "ground_max",
            跨ぎ番号: 最大の跨ぎ番号(集計一覧, 地面の領域番号)?,
        },
        代表点 {
            呼び名: "mirror_max",
            跨ぎ番号: 最大の跨ぎ番号(集計一覧, 鏡の金属の領域番号)?,
        },
        代表点 {
            呼び名: "band_edge",
            跨ぎ番号: 順位の跨ぎ番号(地面の段差の降順, 地面の段差の降順.len() / 10)?,
        },
        代表点 {
            呼び名: "outside_band",
            跨ぎ番号: 順位の跨ぎ番号(地面の段差の降順, 地面の段差の降順.len().saturating_sub(1))?,
        },
    ])
}

fn 最大の跨ぎ番号(集計一覧: &[領域の集計], 領域番号: usize) -> Result<usize, 判定の破れ> {
    集計一覧
        .get(領域番号)
        .map(|集計| 集計.明るさの最大.跨ぎ番号)
        .ok_or_else(|| 判定名を組む(&format!("領域{領域番号}の集計")).あるはずのものが無い破れ())
}

fn 順位の跨ぎ番号(地面の段差の降順: &[(usize, f64)], 順位: usize) -> Result<usize, 判定の破れ> {
    地面の段差の降順
        .get(順位)
        .map(|(番号, _)| *番号)
        .ok_or_else(|| 判定名を組む(&format!("地面の段差の順位{順位}に当たる跨ぎ")).あるはずのものが無い破れ())
}

fn 判定名を組む(綴り: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(綴り.to_string())
}
