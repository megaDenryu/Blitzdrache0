//! 段差の分布の取り方と、全跨ぎにわたる積み上げ。受け取るのは1跨ぎ1領域ぶんの段差、
//! 返すのはその領域の全跨ぎでの最大とその跨ぎである。
//!
//! 最大とp95の2つを採るのは、1画素の外れ値と面としての段差を分けて読むためである。最大は絵の中で最も
//! 段が付いた点を、p95は面のほとんどが動いた量を表す。上限を制定するのはこの実測を読んだ後であり、
//! この入口は判定値を1つも持たない。
//!
//! 全跨ぎにわたる値を「最大の最大」と「p95の最大」として持つのは、跨ぎごとの分布を混ぜた1つの列にすると
//! 「どの跨ぎで起きたか」が消えるためである。跨ぎを名指しできる形で残す。

/// 1跨ぎ1領域ぶんの分布。
pub(super) struct 分布 {
    pub(super) 最大: f64,
    pub(super) p95: f64,
}

/// 全跨ぎにわたる最大と、それが出た跨ぎ。跨ぎを番号で持つのは、区間識別だけでは上りと下りを区別できないためである。
pub(super) struct 最大の記録 {
    pub(super) 値: f64,
    pub(super) 跨ぎ番号: usize,
}

impl 最大の記録 {
    fn 新規() -> Self {
        Self {
            値: f64::NEG_INFINITY,
            跨ぎ番号: 0,
        }
    }

    fn 更新する(&mut self, 値: f64, 跨ぎ番号: usize) {
        if 値 > self.値 {
            *self = Self { 値, 跨ぎ番号 };
        }
    }
}

/// 1つの領域の全跨ぎにわたる積み上げ。
pub(super) struct 領域の集計 {
    pub(super) 名前: String,
    pub(super) 画素数: u64,
    pub(super) 明るさの最大: 最大の記録,
    pub(super) 明るさのp95の最大: 最大の記録,
    pub(super) 色の最大: 最大の記録,
    pub(super) 色のp95の最大: 最大の記録,
    pub(super) 測れなかった画素数: u64,
}

impl 領域の集計 {
    pub(super) fn 新規(名前: String, 画素数: u64) -> Self {
        Self {
            名前,
            画素数,
            明るさの最大: 最大の記録::新規(),
            明るさのp95の最大: 最大の記録::新規(),
            色の最大: 最大の記録::新規(),
            色のp95の最大: 最大の記録::新規(),
            測れなかった画素数: 0,
        }
    }

    pub(super) fn 取り込む(&mut self, 跨ぎ番号: usize, 明るさ: &分布, 色: &分布, 測れなかった画素数: u64) {
        self.明るさの最大.更新する(明るさ.最大, 跨ぎ番号);
        self.明るさのp95の最大.更新する(明るさ.p95, 跨ぎ番号);
        self.色の最大.更新する(色.最大, 跨ぎ番号);
        self.色のp95の最大.更新する(色.p95, 跨ぎ番号);
        self.測れなかった画素数 += 測れなかった画素数;
    }
}

/// 昇順に並べ替えてから最大とp95を採る。百分位の添字は`四捨五入(百分率 × (件数 - 1) ÷ 100)`であり、
/// `hdr-luminance`が採る式と同じである。入口ごとに丸めの向きを別に決めないためである。
pub(super) fn 分布を採る(値一覧: &mut [f64]) -> Result<分布, String> {
    if 値一覧.is_empty() {
        return Err("段差を測れた画素が1つも無い".to_string());
    }
    値一覧.sort_by(f64::total_cmp);
    let 件数 = u64::try_from(値一覧.len()).map_err(|誤り| format!("画素数がu64に収まらない: {誤り}"))?;
    Ok(分布 {
        最大: 値一覧[値一覧.len() - 1],
        p95: 百分位(値一覧, 件数, 95)?,
    })
}

fn 百分位(昇順: &[f64], 件数: u64, 百分率: u64) -> Result<f64, String> {
    let 添字 = usize::try_from((百分率 * (件数 - 1) + 50) / 100).map_err(|誤り| format!("百分位の添字がusizeに収まらない: {誤り}"))?;
    昇順.get(添字).copied().ok_or_else(|| format!("百分位{百分率}の添字{添字}が列の外にある"))
}
