//! 全跨ぎにわたる段差の積み上げ。受け取るのは1跨ぎ1領域ぶんの分布、
//! 返すのはその領域の全跨ぎでの最大とその跨ぎである。
//!
//! 全跨ぎにわたる値を「最大の最大」と「p95の最大」として持つのは、跨ぎごとの分布を混ぜた1つの列にすると
//! 「どの跨ぎで起きたか」が消えるためである。跨ぎを名指しできる形で残す。
//!
//! 1跨ぎ1領域ぶんの分布とその採り方は`distribution`が持つ。積み上げが跨ぎをまたぐ話であるのに対し、
//! そちらは1つの跨ぎの中だけで閉じた話であるためである。

mod distribution;

pub(super) use distribution::{分布, 分布を採る};

/// 全跨ぎにわたる最大と、それが出た跨ぎ。跨ぎを番号で持つのは、区間識別だけでは上りと下りを区別できないためである。
pub(super) struct 最大の記録 {
    pub(super) 値: f64,
    pub(super) 跨ぎ番号: usize,
}

impl 最大の記録 {
    fn 新規() -> Self {
        Self {
            値: f64::NEG_INFINITY,
            跨ぎ番号: 0,
        }
    }

    fn 更新する(&mut self, 値: f64, 跨ぎ番号: usize) {
        if 値 > self.値 {
            *self = Self { 値, 跨ぎ番号 };
        }
    }
}

/// 1つの領域の全跨ぎにわたる積み上げ。
pub(super) struct 領域の集計 {
    pub(super) 名前: String,
    pub(super) 画素数: u64,
    pub(super) 明るさの最大: 最大の記録,
    pub(super) 明るさのp95の最大: 最大の記録,
    pub(super) 色の最大: 最大の記録,
    pub(super) 色のp95の最大: 最大の記録,
    pub(super) 測れなかった画素数: u64,
}

impl 領域の集計 {
    pub(super) fn 新規(名前: String, 画素数: u64) -> Self {
        Self {
            名前,
            画素数,
            明るさの最大: 最大の記録::新規(),
            明るさのp95の最大: 最大の記録::新規(),
            色の最大: 最大の記録::新規(),
            色のp95の最大: 最大の記録::新規(),
            測れなかった画素数: 0,
        }
    }

    pub(super) fn 取り込む(&mut self, 跨ぎ番号: usize, 明るさ: &分布, 色: &分布, 測れなかった画素数: u64) {
        self.明るさの最大.更新する(明るさ.最大, 跨ぎ番号);
        self.明るさのp95の最大.更新する(明るさ.p95, 跨ぎ番号);
        self.色の最大.更新する(色.最大, 跨ぎ番号);
        self.色のp95の最大.更新する(色.p95, 跨ぎ番号);
        self.測れなかった画素数 += 測れなかった画素数;
    }
}
