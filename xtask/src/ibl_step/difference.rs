//! 対の2枚から領域ごとの段差を求める工程。受け取るのは境界の下側と上側の圧縮前HDRと固定領域1つ、
//! 返すのはその領域の画素ごとの明るさの段差と色の段差である。
//!
//! 尺度をEV(2の対数の差)に置くのは、間接照明の段差が明るさの比として効くためである。同じ0.01の差でも
//! 昼の明部では見えず夜の暗部では段になる。8ビットの符号値の差を使えないのは、読むのが明るさの圧縮を通る前の
//! 線形値であり、符号値へ写す関数がまだ掛かっていないためである。
//!
//! 明るさの段差と色の段差を分けるのは、代表値の差が全体を一様に明るくするのか、空の色の傾きを変えるのかで
//! 絵への出方が違うためである。色の段差は成分ごとのEV差から共通の明るさの動きを引いた残りであり、
//! 明るさが揃っていても色だけが動いた段差をこれが捉える。

use super::hdr_image::HDR画像;
use crate::relative_luminance::相対輝度;
use crate::sample_world_region::固定領域;

/// 1つの領域の1つの境界での段差。
pub(super) struct 領域の段差 {
    pub(super) 明るさのev一覧: Vec<f64>,
    pub(super) 色のev一覧: Vec<f64>,
    /// 3成分のどれかが正でないか非有限だったために段差を定められなかった画素の数。
    pub(super) 測れなかった画素数: u64,
}

pub(super) fn 領域の段差を求める(下側: &HDR画像, 上側: &HDR画像, 領域: &固定領域) -> 領域の段差 {
    let mut 段差 = 領域の段差 {
        明るさのev一覧: Vec::with_capacity(領域.画素添字一覧.len()),
        色のev一覧: Vec::with_capacity(領域.画素添字一覧.len()),
        測れなかった画素数: 0,
    };
    for 添字 in &領域.画素添字一覧 {
        match 画素の段差を求める(下側.画素(*添字), 上側.画素(*添字)) {
            Some((明るさ, 色)) => {
                段差.明るさのev一覧.push(明るさ);
                段差.色のev一覧.push(色);
            }
            None => 段差.測れなかった画素数 += 1,
        }
    }
    段差
}

/// 明るさの段差は相対輝度の対数の差、色の段差は成分ごとの対数の差からその明るさの動きを引いた残りの最大である。
/// どちらか一方でも定まらない画素は測れなかったものとして数え、黙って0として混ぜない。
fn 画素の段差を求める(下側: &[f32], 上側: &[f32]) -> Option<(f64, f64)> {
    let 明るさ = 対数の差(相対輝度(下側), 相対輝度(上側))?;
    let mut 色の最大 = 0.0;
    for 成分 in 0..3 {
        let 成分の差 = 対数の差(f64::from(下側[成分]), f64::from(上側[成分]))?;
        色の最大 = f64::max(色の最大, (成分の差 - 明るさ).abs());
    }
    Some((明るさ.abs(), 色の最大))
}

/// 2の対数の差。対数は正の値にしか定まらないため、0以下と非有限は差を定めない。
fn 対数の差(下側: f64, 上側: f64) -> Option<f64> {
    if 下側 <= 0.0 || 上側 <= 0.0 || !下側.is_finite() || !上側.is_finite() {
        return None;
    }
    Some(上側.log2() - 下側.log2())
}
