//! 段差を撮る起動の指定と、撮影1枚ぶんの名前の組み立て。受け取るのは撮るもの、返すのは実行環境へ渡す
//! 起動指定である。起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! 一日ぶんを1回の起動で撮らずに束へ切るのは、1撮影の圧縮前HDRが1枚十数メガバイトあり、
//! 一日ぶんを残したままにすると数十ギガバイトを占めるためである。束ごとに読み終えた生の画像を捨てて進む。
//!
//! リリースで走らせるのは、1束が数十枚の画素をCPUへ運んで書き出すためである。画素の値は最適化水準で変わらない。
//! 時間再構成は`--no-taa`で外す。この入口の判定がバイト一致に依るため、フレームをまたぐ混合が入ると前のフレームの残りが絵に混ざる。

use std::path::PathBuf;

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 描画フレーム数, 描画検収の実行環境, 検収の実行名, 検収エラー
};
use crate::visual_sample_world::{目視見本世界のアセットルートを作る, 目視見本世界のシーン名};

/// 走査の起動が描く枚数。アプリが跨ぎごとに時計を据え直して撮るため、この枚数は1撮影ぶんの歩進である。
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(12);

/// 走査の起動の書き出しの基準名。アプリがこの名前へ跨ぎと向きと側の語を足して1枚ずつ書き出す。
pub(super) const 撮影の実行名: 検収の実行名 = 検収の実行名::定数から生成する("shot");
/// 代表点の絵の書き出しの基準名。走査の生の画像を束ごとに捨てる一方、代表点の対は目視の材料として残すため、
/// 走査と別の基準名にする。
pub(super) const 絵の実行名: 検収の実行名 = 検収の実行名::定数から生成する("picture");

/// 1回の起動が何を撮るか。走査の指定の枝と1対1に対応する。
pub(super) enum 撮るもの<'指定> {
    /// 跨ぎの範囲を圧縮前のHDRで撮る。段差を測る本体である。
    範囲の段差 { 最初の跨ぎ番号: usize, 跨ぎの件数: usize },
    /// 1つの跨ぎを下側・上側・下側の順に圧縮前のHDRで撮る。持ち越しと一回限りの揺れを反証する。
    跨ぎの対照 { 跨ぎ番号: usize },
    /// 1つの跨ぎの対を、明るさの圧縮を通した提示画像で撮る。オーナーが絵で見る材料である。
    /// 自動露出を外すのは、対の2枚を同じ露出条件に揃えるためである。露出が別々に追従すると、
    /// 見えている差が間接照明の段差なのか露出の違いなのか決められない。
    跨ぎの絵 { 跨ぎ番号: usize, 呼び名: &'指定 str },
}

impl 撮るもの<'_> {
    /// 失敗の文面へ出すその撮影の呼び名。
    pub(super) fn 条件名(&self) -> String {
        match self {
            Self::範囲の段差 {
                最初の跨ぎ番号, 跨ぎの件数
            } => format!("跨ぎ番号{最初の跨ぎ番号}から{跨ぎの件数}件"),
            Self::跨ぎの対照 { 跨ぎ番号 } => format!("跨ぎ番号{跨ぎ番号}の対照"),
            Self::跨ぎの絵 { 跨ぎ番号, 呼び名 } => format!("跨ぎ番号{跨ぎ番号}の絵({呼び名})"),
        }
    }
}

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoにリリース版を構築させ構築の知らせを伏せて起動する,
        目視見本世界のアセットルートを作る(),
        出力ディレクトリ,
    )
}

pub(super) fn 起動指定を組み立てる(撮るもの: &撮るもの<'_>) -> アプリの起動指定 {
    let 指定 = アプリの起動指定::シーンと枚数を決める(目視見本世界のシーン名, フレーム数).選択肢を足す("--no-taa");
    match 撮るもの {
        撮るもの::範囲の段差 {
            最初の跨ぎ番号, 跨ぎの件数
        } => 指定.値を持つ選択肢を足す("--ibl-step-scan", &format!("{最初の跨ぎ番号},{跨ぎの件数}")),
        撮るもの::跨ぎの対照 { 跨ぎ番号 } => 指定.値を持つ選択肢を足す("--ibl-step-control", &跨ぎ番号.to_string()),
        撮るもの::跨ぎの絵 { 跨ぎ番号, .. } => 指定
            .値を持つ選択肢を足す("--ibl-step-scan", &format!("{跨ぎ番号},1"))
            .選択肢を足す("--no-auto-exposure"),
    }
}

/// その撮影1枚ぶんの実行名。blitz_app側が基準名へ足す後置きと同じ形をここでも組む。
/// 形を1つの関数に閉じるのは、書く側と読む側の食い違いが「ファイルが無い」という遠い失敗に化けるためである。
pub(super) fn 撮影1枚の実行名(
    基準名: 検収の実行名, 上側の区間識別: u16, 方向: &str, 側: &str
) -> Result<検収の実行名, 検収エラー> {
    検収の実行名::生成する(&format!("{基準名}_{上側の区間識別}_{方向}_{側}"))
}
