//! 束ごとの撮影と、読み終えた生の画像の後始末。受け取るのは実行環境と束の範囲か1件の跨ぎ、返すものは無い。
//!
//! 撮ることと捨てることを1つのファイルが持つのは、この2つが同じ置き場の同じ書き出し名を対にして扱うためである。
//! 捨てる側だけが名前の組み方を取り違えると、消えなかった生の画像が一日ぶん積み上がる。

use super::super::crossing::跨ぎ;
use super::super::run;
use crate::acceptance::{描画検収の実行環境, 書き出しの形式, 検収エラー};

/// 走査が1つの跨ぎで撮る側の語。段差は下側と上側の対で測る。
const 対の2つの側: [&str; 2] = ["low", "high"];

pub(super) fn 一束を撮る(
    実行環境: &描画検収の実行環境, 最初の跨ぎ番号: usize, 跨ぎの件数: usize
) -> Result<(), 検収エラー> {
    let 撮るもの = run::撮るもの::範囲の段差 {
        最初の跨ぎ番号, 跨ぎの件数
    };
    println!("[xtask] ibl-step撮影: {}", 撮るもの.条件名());
    実行環境.書き出させて報告を採る(run::撮影の実行名, &run::起動指定を組み立てる(&撮るもの), 書き出しの形式::明るさの圧縮前)?;
    Ok(())
}

/// 読み終えた1件の生の画像を捨てる。次の束が同じ場所へ書くわけではないため、消さないと一日ぶんが積み上がる。
pub(super) fn 一件の撮影を捨てる(実行環境: &描画検収の実行環境, 跨ぎ: &跨ぎ) {
    for 側 in 対の2つの側 {
        if let Ok(実行名) = run::撮影1枚の実行名(run::撮影の実行名, 跨ぎ.上側の区間識別, &跨ぎ.方向, 側) {
            実行環境.同じ置き場の書き出しを捨てる(実行名);
        }
    }
}
