//! 代表点の絵の書き出し。受け取るのは跨ぎの一覧と領域ごとの集計と地面の段差の順位、返すのは書き出したPNGの
//! 置き場の一覧である。
//!
//! 全跨ぎを絵にしないのは、刻みの裁定に要るのが「段差が最も大きいところはどう見えるか」と
//! 「小さいところでは本当に見えないか」であり、その2つは順位で選んだ数点で足りるためである。
//!
//! 選ぶ点を段差の閾値でなく順位で決めるのは、閾値を置くとこの入口が判定値を持ってしまうためである。
//! この入口は上限を1つも持たず、観測だけを行う。
//!
//! 絵は明るさの圧縮を通した提示画像であり、対の2枚は自動露出を外して同じ露出条件で撮る。
//! 露出が別々に追従すると、見えている差が間接照明の段差なのか露出の違いなのか決められない。

use super::crossing::跨ぎ;
use super::run;
use super::scan::地面の領域番号;
use super::summary::領域の集計;
use crate::acceptance::{描画検収の実行環境, 書き出しの形式};

/// 代表点の絵が撮る側の語。対の2枚を並べて見る。
const 対の2つの側: [&str; 2] = ["low", "high"];

/// 鏡の金属の領域の並び順。地面の次が金属の粗さの昇順であるため、その次が粗さ0の球である。
const 鏡の金属の領域番号: usize = 1;

/// 順位で選んだ代表点。呼び名はファイル名に使うためASCIIで持つ。
struct 代表点 {
    呼び名: &'static str,
    跨ぎ番号: usize,
}

pub(super) fn 代表点の絵を書く(
    実行環境: &描画検収の実行環境,
    跨ぎ一覧: &[跨ぎ],
    集計一覧: &[領域の集計],
    地面の段差の降順: &[(usize, f64)],
) -> Result<Vec<String>, String> {
    let mut 置き場一覧 = Vec::new();
    for 点 in 代表点を選ぶ(集計一覧, 地面の段差の降順)? {
        let 該当 = 跨ぎ一覧
            .get(点.跨ぎ番号)
            .ok_or_else(|| format!("代表点の跨ぎ番号{}が一覧の外にある", 点.跨ぎ番号))?;
        let 撮るもの = run::撮るもの::跨ぎの絵 {
            跨ぎ番号: 点.跨ぎ番号,
            呼び名: 点.呼び名,
        };
        println!("[xtask] ibl-step撮影: {}", 撮るもの.条件名());
        実行環境.書き出させて報告を採る(run::絵の実行名, &run::起動指定を組み立てる(&撮るもの), 書き出しの形式::提示画像)?;
        for 側 in 対の2つの側 {
            let 実行名 = run::撮影1枚の実行名(run::絵の実行名, 該当.上側の区間識別, &該当.方向, 側)?;
            let 置き場 = 実行環境.同じ置き場の書き出しを目視用の絵へ変換する(実行名)?;
            置き場一覧.push(format!("{}({})", 置き場.display(), 点.呼び名));
        }
    }
    Ok(置き場一覧)
}

/// 代表点は4つである。地面の段差が最大の跨ぎ、鏡の金属の段差が最大の跨ぎ、地面の段差の順位が上から1割の跨ぎ
/// (帯の端に当たる)、地面の段差が最小の跨ぎ(帯の外)である。
fn 代表点を選ぶ(集計一覧: &[領域の集計], 地面の段差の降順: &[(usize, f64)]) -> Result<Vec<代表点>, String> {
    Ok(vec![
        代表点 {
            呼び名: "ground_max",
            跨ぎ番号: 最大の跨ぎ番号(集計一覧, 地面の領域番号)?,
        },
        代表点 {
            呼び名: "mirror_max",
            跨ぎ番号: 最大の跨ぎ番号(集計一覧, 鏡の金属の領域番号)?,
        },
        代表点 {
            呼び名: "band_edge",
            跨ぎ番号: 順位の跨ぎ番号(地面の段差の降順, 地面の段差の降順.len() / 10)?,
        },
        代表点 {
            呼び名: "outside_band",
            跨ぎ番号: 順位の跨ぎ番号(地面の段差の降順, 地面の段差の降順.len().saturating_sub(1))?,
        },
    ])
}

fn 最大の跨ぎ番号(集計一覧: &[領域の集計], 領域番号: usize) -> Result<usize, String> {
    集計一覧
        .get(領域番号)
        .map(|集計| 集計.明るさの最大.跨ぎ番号)
        .ok_or_else(|| format!("領域{領域番号}の集計が無い"))
}

fn 順位の跨ぎ番号(地面の段差の降順: &[(usize, f64)], 順位: usize) -> Result<usize, String> {
    地面の段差の降順
        .get(順位)
        .map(|(番号, _)| *番号)
        .ok_or_else(|| format!("地面の段差の順位{順位}が一覧の外にある"))
}
