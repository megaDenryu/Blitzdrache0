//! 間引きの段差の計測エラーを人が読む1文へ写すトレイト実装。枝ごとに、どの前提がどう破れたかを出す。
//! 実装を型の定義と分けるのは、外部トレイトの実装が型自身の持ち物とは別の軸であるためである。

use std::fmt;

use super::間引きの段差の計測エラー;

impl fmt::Display for 間引きの段差の計測エラー {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::検収の器が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::判定が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::目視見本世界を用意できなかった(破れ) => write!(書き手, "{破れ}"),
            Self::固定領域の一覧を作れなかった { 理由 } => write!(書き手, "{理由}"),
            Self::画素数が数へ収まらない { 画素数 } => write!(書き手, "画素数{画素数}が数へ収まらない"),
            Self::百分位の添字が数へ収まらない { 百分率, 添字 } => {
                write!(書き手, "百分位{百分率}の添字{添字}が数へ収まらない")
            }
            Self::百分位の添字が列の外にある { 百分率, 添字 } => {
                write!(書き手, "百分位{百分率}の添字{添字}が列の外にある")
            }
            Self::生値を書けなかった { パス, 誤り } => {
                write!(書き手, "{}を書けなかった: {誤り}", パス.display())
            }
        }
    }
}
