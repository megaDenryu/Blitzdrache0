//! 1跨ぎ1領域ぶんの段差の分布と、その採り方。受け取るのは段差の値の列、返すのは最大とp95である。
//!
//! 最大とp95の2つを採るのは、1画素の外れ値と面としての段差を分けて読むためである。最大は絵の中で最も
//! 段が付いた点を、p95は面のほとんどが動いた量を表す。上限を制定するのはこの実測を読んだ後であり、
//! この入口は判定値を1つも持たない。

use super::super::error::間引きの段差の計測エラー;
use crate::acceptance::判定の名前;

const 段差を測れた画素: 判定の名前 = 判定の名前::定数から生成する("段差を測れた画素");

/// 1跨ぎ1領域ぶんの分布。
pub(in super::super) struct 分布 {
    pub(in super::super) 最大: f64,
    pub(in super::super) p95: f64,
}

/// 昇順に並べ替えてから最大とp95を採る。百分位の添字は`四捨五入(百分率 × (件数 - 1) ÷ 100)`であり、
/// `hdr-luminance`が採る式と同じである。入口ごとに丸めの向きを別に決めないためである。
pub(in super::super) fn 分布を採る(値一覧: &mut [f64]) -> Result<分布, 間引きの段差の計測エラー> {
    if 値一覧.is_empty() {
        return Err(段差を測れた画素.あるはずのものが無い破れ().into());
    }
    値一覧.sort_by(f64::total_cmp);
    let 件数 = u64::try_from(値一覧.len())
        .map_err(|_| 間引きの段差の計測エラー::画素数が数へ収まらない { 画素数: 値一覧.len() })?;
    Ok(分布 {
        最大: 値一覧[値一覧.len() - 1],
        p95: 百分位(値一覧, 件数, 95)?,
    })
}

fn 百分位(昇順: &[f64], 件数: u64, 百分率: u64) -> Result<f64, 間引きの段差の計測エラー> {
    let 求めた添字 = (百分率 * (件数 - 1) + 50) / 100;
    let 添字 = usize::try_from(求めた添字)
        .map_err(|_| 間引きの段差の計測エラー::百分位の添字が数へ収まらない {
            百分率, 添字: 求めた添字
        })?;
    昇順
        .get(添字)
        .copied()
        .ok_or(間引きの段差の計測エラー::百分位の添字が列の外にある { 百分率, 添字 })
}
