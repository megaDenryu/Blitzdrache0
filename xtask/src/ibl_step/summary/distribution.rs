//! 1跨ぎ1領域ぶんの段差の分布と、その採り方。受け取るのは段差の値の列、返すのは最大と95パーセンタイル値である。
//!
//! 最大と95パーセンタイル値の2つを採るのは、1画素の外れ値と面としての段差を分けて読むためである。最大は絵の中で最も
//! 段が付いた点を、95パーセンタイル値は面のほとんどが動いた量を表す。上限を制定するのはこの実測を読んだ後であり、
//! この入口は判定値を1つも持たない。

use blitz_math::{パーセンタイル順位, 昇順に並べた標本列, 順位から添字を選ぶ規則};

use super::super::error::間引きの段差の計測エラー;
use crate::acceptance::判定の名前;

const 段差を測れた画素: 判定の名前 = 判定の名前::定数から生成する("段差を測れた画素");
/// この分布が読む順位と、添字を選ぶ規則。寄せる前からこの規則であり、報告の値を動かさないために変えない。
const 面の代表の順位: f32 = 95.0;
const 添字を選ぶ規則: 順位から添字を選ぶ規則 = 順位から添字を選ぶ規則::最後の添字を基準にした四捨五入;

/// 1跨ぎ1領域ぶんの分布。
pub(in super::super) struct 分布 {
    pub(in super::super) 最大: f64,
    pub(in super::super) 九十五パーセンタイル値: f64,
}

/// 昇順に並べ替えてから最大と面の代表の段差を採る。添字を選ぶ規則は`hdr-luminance`が採る規則と同じである。
/// 入口ごとに丸めの向きを別に決めないためである。
pub(in super::super) fn 分布を採る(値一覧: &mut [f64]) -> Result<分布, 間引きの段差の計測エラー> {
    if 値一覧.is_empty() {
        return Err(段差を測れた画素.あるはずのものが無い破れ().into());
    }
    let 標本列 = 昇順に並べた標本列::並べ替えて生成する(値一覧);
    let 採れなかった = || 間引きの段差の計測エラー::パーセンタイル値を採れなかった {
        順位: 面の代表の順位, 件数: 標本列.件数()
    };
    Ok(分布 {
        最大: 標本列.最大().ok_or_else(採れなかった)?,
        九十五パーセンタイル値: 標本列.パーセンタイル値を求める(パーセンタイル順位::百分率から生成する(面の代表の順位), 添字を選ぶ規則).ok_or_else(採れなかった)?,
    })
}
