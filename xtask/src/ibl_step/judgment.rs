//! この入口が持つ機械判定。受け取るのは領域ごとの集計と跨ぎの一覧、返すのは合否と、対照が確かめた事実の1行である。
//!
//! 判定を段取りから分けるのは、「この入口が何を落とすか」を1箇所で読めるようにするためである。
//! 上限は1つも持たない。段差の大きさの合否はこの実測を読んだ後にオーナーが制定する。

use super::crossing::跨ぎ;
use super::summary::領域の集計;
use super::{control, scan};
use crate::acceptance::{判定の名前, 判定の破れ, 描画検収の実行環境, 検収エラー};

const 地面の集計: 判定の名前 = 判定の名前::定数から生成する("固定領域の一覧の中の地面の集計");

/// 報告する値がすべて有限であることを見る。非有限は測り方が壊れたことを意味し、値の大きさとは別の話である。
pub(super) fn 値が有限であることを確かめる(集計一覧: &[領域の集計]) -> Result<(), 判定の破れ> {
    for 集計 in 集計一覧 {
        for (呼び名, 値) in [
            ("明るさの最大", 集計.明るさの最大.値),
            ("明るさの第95百分位の最大", 集計.明るさの第95百分位の最大.値),
            ("色の最大", 集計.色の最大.値),
            ("色の第95百分位の最大", 集計.色の第95百分位の最大.値),
        ] {
            判定名を組む(&format!("{}の{呼び名}", 集計.名前)).有限であることを課す(値)?;
        }
    }
    Ok(())
}

/// 代表点のA/B/A対照。地面の段差が最も大きい跨ぎで撮るのは、下側と上側が一致しないことを同時に要求するためであり、
/// 段差が0の跨ぎで撮ると「変わらないこと」しか確かめられないためである。
pub(super) fn 対照を判定する(
    実行環境: &描画検収の実行環境, 跨ぎ一覧: &[跨ぎ], 集計一覧: &[領域の集計]
) -> Result<String, 検収エラー> {
    let 番号 = 集計一覧
        .get(scan::地面の領域番号)
        .map(|集計| 集計.明るさの最大.跨ぎ番号)
        .ok_or_else(|| 地面の集計.あるはずのものが無い破れ())?;
    let 跨ぎ = 跨ぎ一覧
        .get(番号)
        .ok_or_else(|| 判定名を組む(&format!("対照の跨ぎ番号{番号}に当たる跨ぎ")).あるはずのものが無い破れ())?;
    control::判定する(
        実行環境,
        &control::対照の対象 {
            跨ぎ番号: 番号,
            上側の区間識別: 跨ぎ.上側の区間識別,
            方向: &跨ぎ.方向,
        },
    )
}

fn 判定名を組む(綴り: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(綴り.to_string())
}
