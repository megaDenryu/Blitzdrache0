//! 跨ぎの報告の解析。受け取るのは終了時報告、返すのは跨ぎの一覧か、読めなかった理由である。
//!
//! 起動から分けるのは、この工程が報告の中身だけを材料にし、GPUもプロセスも要らないためである。単体検査が
//! 壊れた行と総数の食い違いを直に与えられる。
//!
//! どの検査も「読めた行だけを使う」ことをしない。1行の形式が変わっただけで検収が黙って少ない件数を測り、
//! 成功として終わってしまうためである。

use crate::acceptance::{判定の名前, 報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

/// 1つの跨ぎ。段差を測る対はこの跨ぎの下側と上側の区間で撮られる。
#[derive(Debug)]
pub(in super::super) struct 跨ぎ {
    pub(in super::super) 上側の区間識別: u16,
    pub(in super::super) 方向: String, // 跨ぐ向きの語。報告が出すASCIIの語をそのまま持ち、ファイル名にも使う
    pub(in super::super) 境界の天頂余弦: f64,
    pub(in super::super) 一日内秒: f64,
}

const 見出しの前置き: 報告の見出し = 報告の見出し::定数から生成する("太陽天頂区間の跨ぎ報告 ");
const 行の前置き: 報告の見出し = 報告の見出し::定数から生成する("太陽天頂区間の跨ぎ 番号=");
/// この報告の行は全項目が「鍵=値」の形で空白区切りに並ぶ。
const 値の結ばれ方: 鍵に値が結ばれる形 = 鍵に値が結ばれる形::等号の後ろが値である;

const 跨ぎの行数: 判定の名前 = 判定の名前::定数から生成する("見出しが言う総数に対する跨ぎの行数");
/// 番号が0からの連番であることを課す。飛んだ番号を詰めて読むと、別の跨ぎの区間で撮った対を測る。
const 跨ぎの行の番号: 判定の名前 = 判定の名前::定数から生成する("跨ぎの行の番号(0からの連番でなければならない)");

pub(in super::super) fn 一覧を読む(報告: &終了時報告) -> Result<Vec<跨ぎ>, 検収エラー> {
    let 総数: usize = 報告.見出しの1行(&見出しの前置き)?.鍵に結ばれた数(&鍵を組む("跨ぎの総数"), 値の結ばれ方)?;
    let mut 一覧 = Vec::with_capacity(総数);
    for 行 in 報告.見出しで始まる行の一覧(&行の前置き) {
        let 番号: usize = 数を読む(&行, "番号")?;
        跨ぎの行の番号.一致を課す(番号, 一覧.len())?;
        一覧.push(跨ぎを読む(&行)?);
    }
    跨ぎの行数.一致を課す(一覧.len(), 総数)?;
    Ok(一覧)
}

fn 跨ぎを読む(行: &報告の行) -> Result<跨ぎ, 検収エラー> {
    Ok(跨ぎ {
        上側の区間識別: 数を読む(行, "上側の区間識別")?,
        方向: 行.鍵に結ばれた綴り(&鍵を組む("方向"), 値の結ばれ方)?,
        境界の天頂余弦: 数を読む(行, "境界の天頂余弦")?,
        一日内秒: 数を読む(行, "一日内秒")?,
    })
}

fn 数を読む<数: std::str::FromStr>(行: &報告の行, 鍵の綴り: &str) -> Result<数, 検収エラー> {
    行.鍵に結ばれた数(&鍵を組む(鍵の綴り), 値の結ばれ方)
}

fn 鍵を組む(綴り: &str) -> 報告の行の鍵 {
    報告の行の鍵::組み立てた綴りから生成する(綴り.to_string())
}
