//! 対照の判定。受け取るのは実行環境と跨ぎ1件、返すのは判定の結果を述べる1行である。
//!
//! 見るのは2つである。同じ下側の区間で撮った1枚目と3枚目がバイト一致すること(区間を差し替えた後に戻すと
//! 元の絵へ戻る=焼き上げに状態の持ち越しが無い)と、下側と上側が一致しないこと(その跨ぎで段差が実在する)である。
//!
//! 全跨ぎを3枚にしないのは、この2つが撮り方そのものの性質であり、段差が非0の代表点1つで反証できるためである。
//! 代表点を表で持たず実測から選ぶのは、刻みを変えると段差が非0になる跨ぎも変わるためである。

use super::run;
use crate::acceptance::{圧縮前のHDR画像, 描画検収の実行環境, 書き出しの形式};

/// 対照が撮る3枚の側の語。1枚目と3枚目が同じ下側の区間である。
const 対照の3つの側: [&str; 3] = ["low", "high", "low2"];

pub(super) struct 対照の対象<'呼び名> {
    pub(super) 跨ぎ番号: usize,
    pub(super) 上側の区間識別: u16,
    pub(super) 方向: &'呼び名 str,
}

pub(super) fn 判定する(実行環境: &描画検収の実行環境, 対象: &対照の対象<'_>) -> Result<String, String> {
    let 撮るもの = run::撮るもの::跨ぎの対照 {
        跨ぎ番号: 対象.跨ぎ番号
    };
    実行環境.書き出させて報告を採る(run::撮影の実行名, &run::起動指定を組み立てる(&撮るもの), 書き出しの形式::明るさの圧縮前)?;
    let 読む = |側: &str| 一枚を読む(実行環境, 対象, 側);
    let (一枚目, 上側, 三枚目) = (読む("low")?, 読む("high")?, 読む("low2")?);
    let 名指し = format!("跨ぎ(区間識別{} {})", 対象.上側の区間識別, 対象.方向);
    if !一枚目.成分がビット単位で同じか(&三枚目) {
        return Err(format!("{名指し}の対照で、同じ下側の区間の1枚目と3枚目がバイト一致しなかった"));
    }
    if 一枚目.成分がビット単位で同じか(&上側) {
        return Err(format!("{名指し}の対照で、下側と上側の区間の絵がバイト一致した(この跨ぎに段差が無い)"));
    }
    後始末する(実行環境, 対象);
    Ok(format!("{名指し}のA/B/A対照は1枚目と3枚目がバイト一致し、下側と上側は一致しない"))
}

fn 一枚を読む(実行環境: &描画検収の実行環境, 対象: &対照の対象<'_>, 側: &str) -> Result<圧縮前のHDR画像, String> {
    Ok(実行環境.同じ置き場の圧縮前の画素を読み戻す(撮影1枚の実行名(対象, 側)?)?)
}

fn 撮影1枚の実行名(
    対象: &対照の対象<'_>, 側: &str
) -> Result<crate::acceptance::検収の実行名, crate::acceptance::検収エラー> {
    run::撮影1枚の実行名(run::撮影の実行名, 対象.上側の区間識別, 対象.方向, 側)
}

fn 後始末する(実行環境: &描画検収の実行環境, 対象: &対照の対象<'_>) {
    for 側 in 対照の3つの側 {
        if let Ok(実行名) = 撮影1枚の実行名(対象, 側) {
            実行環境.同じ置き場の書き出しを捨てる(実行名);
        }
    }
}
