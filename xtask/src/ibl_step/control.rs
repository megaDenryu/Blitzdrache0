//! 対照の判定。受け取るのは跨ぎ1件と書き出しのベース名、返すのは判定の結果を述べる1行である。
//!
//! 見るのは2つである。同じ下側の区間で撮った1枚目と3枚目がバイト一致すること(区間を差し替えた後に戻すと
//! 元の絵へ戻る=焼き上げに状態の持ち越しが無い)と、下側と上側が一致しないこと(その跨ぎで段差が実在する)である。
//!
//! 全跨ぎを3枚にしないのは、この2つが撮り方そのものの性質であり、段差が非0の代表点1つで反証できるためである。
//! 代表点を表で持たず実測から選ぶのは、刻みを変えると段差が非0になる跨ぎも変わるためである。

use std::path::Path;

use super::run;

pub(super) struct 対照の対象<'呼び名> {
    pub(super) 跨ぎ番号: usize,
    pub(super) 上側の区間識別: u16,
    pub(super) 方向: &'呼び名 str,
}

pub(super) fn 判定する(対象: &対照の対象<'_>, ベース名: &Path) -> Result<String, String> {
    run::撮る(
        &run::撮るもの::跨ぎの対照 {
            跨ぎ番号: 対象.跨ぎ番号
        },
        ベース名,
    )?;
    let 読む = |側: &str| 中身を読む(&run::撮影のベース名(ベース名, 対象.上側の区間識別, 対象.方向, 側));
    let (一枚目, 上側, 三枚目) = (読む("low")?, 読む("high")?, 読む("low2")?);
    let 名指し = format!("跨ぎ(区間識別{} {})", 対象.上側の区間識別, 対象.方向);
    if 一枚目 != 三枚目 {
        return Err(format!("{名指し}の対照で、同じ下側の区間の1枚目と3枚目がバイト一致しなかった"));
    }
    if 一枚目 == 上側 {
        return Err(format!("{名指し}の対照で、下側と上側の区間の絵がバイト一致した(この跨ぎに段差が無い)"));
    }
    後始末する(ベース名, 対象);
    Ok(format!("{名指し}のA/B/A対照は1枚目と3枚目がバイト一致し、下側と上側は一致しない"))
}

fn 中身を読む(基準: &Path) -> Result<Vec<u8>, String> {
    let パス = 基準.with_extension("hdr32");
    std::fs::read(&パス).map_err(|誤り| format!("{}を読めない: {誤り}", パス.display()))
}

fn 後始末する(ベース名: &Path, 対象: &対照の対象<'_>) {
    for 側 in ["low", "high", "low2"] {
        let 基準 = run::撮影のベース名(ベース名, 対象.上側の区間識別, 対象.方向, 側);
        for 拡張子 in ["hdr32", "size"] {
            let _ = std::fs::remove_file(基準.with_extension(拡張子));
        }
    }
}
