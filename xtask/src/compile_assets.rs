//! ソースアセットを版付き実行時形式へ変換する唯一の公開ツール入口。
//! 1つの出力ルートは1つのチャンク世界を持つため、世界ごとに出力ルートを分けて順に生成する。
//! 焼ける世界の数え上げは`world_name`が、テクスチャ格納方針を指す綴りは`texture_policy_name`が、
//! 世界ごとの既定出力ルートは`default_root`が、コンパイラの起動は`invoke`が、コマンド行の引数の解釈は`command_arguments`が持つ。

mod command_arguments;
mod default_root;
mod invoke;
pub mod texture_policy_name;
mod world_name;

use std::path::Path;

pub use command_arguments::実行する;
pub use default_root::*;
pub use world_name::*;

use invoke::{
    アセットコンパイラを起動して実行時形式を焼く, アセットコンパイラを起動して標準出力を取り込む, 実行時形式を焼く指定
};

pub fn 生成する(ソースルート: &Path, 出力ルート: &Path, 世界: 世界名) -> bool {
    個体数を添えて生成する(ソースルート, 出力ルート, 世界, None)
}

/// ソースルートと出力ルートを名指しして焼き、コンパイラの標準出力を返す。焼き直した本数を読む検収がこの入口を通る。
pub fn ルートを名指しして焼き標準出力を返す(
    ソースルート: &Path, 出力ルート: &Path, 世界: 世界名
) -> Result<String, String> {
    アセットコンパイラを起動して標準出力を取り込む(&実行時形式を焼く指定 {
        ソースルート,
        出力ルート,
        世界,
        同居植生個体数: None,
        テクスチャ格納方針の名前: None,
    })
}

/// テクスチャ格納方針を名指しして焼く。既定を当てはめずに方針を渡すのは`cargo xtask texture-compression`だけであり、
/// この入口が同じ世界を方針違いで2度焼いて絵と格納バイト数の対照を作る。
/// 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`「判断i」
pub fn 方針を名指しして実行時形式を生成する(
    出力ルート: &Path, 世界: 世界名, テクスチャ格納方針の名前: &str
) -> bool {
    アセットコンパイラを起動して実行時形式を焼く(&実行時形式を焼く指定 {
        ソースルート: default_root::ソースルート(),
        出力ルート,
        世界,
        同居植生個体数: None,
        テクスチャ格納方針の名前: Some(テクスチャ格納方針の名前),
    })
}

/// 地形世界の同居植生を指定の密度で焼く。物量計測が原型・マテリアル・座標を固定したまま密度だけを変えるための入口である。
pub fn 地形世界を個体数指定で生成する(出力ルート: &Path, 個体数: usize) -> bool {
    世界を個体数指定で生成する(出力ルート, 世界名::地形の世界, 個体数)
}

/// 地形の目録を持つ世界の同居植生を、指定の密度で焼く。既定の出力ルートと衝突しないよう呼び出し側が専用の出力ルートを渡す。
/// 頂点診断の世界は代表世界と同じ地面と密度を使うため、世界名だけを差し替えれば条件間で配置が揃う。
pub fn 世界を個体数指定で生成する(出力ルート: &Path, 世界: 世界名, 個体数: usize) -> bool {
    let 個体数 = 個体数.to_string();
    個体数を添えて生成する(default_root::ソースルート(), 出力ルート, 世界, Some(&個体数))
}

pub(super) fn 個体数を添えて生成する(
    ソースルート: &Path, 出力ルート: &Path, 世界: 世界名, 同居植生個体数: Option<&str>
) -> bool {
    アセットコンパイラを起動して実行時形式を焼く(&実行時形式を焼く指定 {
        ソースルート,
        出力ルート,
        世界,
        同居植生個体数,
        テクスチャ格納方針の名前: None,
    })
}
