//! 間接照明の費用計測が返す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。
//! 様式は`acceptance/error.rs`と`acceptance/error/readback_break.rs`に倣う。
//!
//! 検収の器の破れと判定の破れを枝で内包するのは、この入口が起動と読み取りと判定とファイルの書き出しを
//! 一続きに通すためである。4つを別の型で返すと、通す側が段ごとに変換を書くことになる。
//!
//! 引数の解釈とファイルの書き出しをここが持つのは、どちらも判定でも報告の読み取りでもないためである。
//! 構築とシェーダーの一時コピーの破れを枝で内包するのは、その2つが別の入口の持ち物であり、
//! 破れの数え上げをそれぞれの入口が持つためである。人が読む1文へ写すのは`display`が持つ。

mod display;

use std::path::PathBuf;

use crate::acceptance::{判定の破れ, 検収エラー};

#[derive(Debug)]
pub(super) enum 間接照明の費用計測エラー {
    検収の器が破れた(検収エラー),
    判定が破れた(判定の破れ),
    知らない引数を渡された {
        語: String,
    },
    引数の次に値が無い {
        引数名: &'static str,
    },
    引数の値を数として読めない {
        引数名: &'static str,
        語: String,
    },
    /// 1フレームも描かない実行は計器の窓を1つも埋めず、分位が定義できない。
    フレーム数が零である,
    検証用アセットを生成できなかった,
    出力先を作れなかった {
        誤り: std::io::Error,
    },
    実行の標準出力を書けなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    生値を書けなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    計測用の構築が失敗した(crate::release_build::計測用の構築の破れ),
    シェーダーの一時コピーを作れなかった(crate::shader_copy::シェーダーの一時コピーの破れ),
}

impl std::error::Error for 間接照明の費用計測エラー {}

impl From<検収エラー> for 間接照明の費用計測エラー {
    fn from(破れ: 検収エラー) -> Self {
        Self::検収の器が破れた(破れ)
    }
}

impl From<判定の破れ> for 間接照明の費用計測エラー {
    fn from(破れ: 判定の破れ) -> Self {
        Self::判定が破れた(破れ)
    }
}
