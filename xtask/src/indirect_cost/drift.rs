//! 停止Aと停止A'の食い違いを1文にする工程。受け取るのは同じ条件の2標本、返すのは区間別の食い違いを並べた文である。
//!
//! 判定と別に置くのは、ここが合否を1つも出さないためである。同じ条件どうしの比較であり、ここに出る差は条件の差ではなく
//! 機材の状態の移り変わりである。線を引くのは読み手が見落とさないようにするためであって、実行を落とすためではない。
//!
//! 区間別に出すのは、消費・間接照明生成の合計・局所可視性の2区間が60標本の定常区間であり、反射率積分表が
//! 起動後1回の単発だからである。混ぜて1つの数にすると、単発の値の揺れが定常の揺れとして読まれる。

#[cfg(test)]
mod tests;

use super::intervals;
use super::record::一標本;

/// 停止Aと停止A'の食い違いがこの割合を超えたら、条件の差でなく機材の状態が動いたものとして報告に明示する。
/// 判定には使わない。
/// シャドウの律速切り分けでは同じ条件のあいだで合計が3.13ミリ秒から4.31ミリ秒(38パーセント)まで動いており、その規模を読み手が見落とさない位置に線を引いている。
const 交絡を告げる割合: f64 = 0.10;

pub(super) fn 交互実行の食い違い(停止a: &一標本, 停止a2: &一標本) -> String {
    let 区間一覧 = [
        (intervals::消費の区間名, "60標本の定常"),
        (intervals::生成の合計の区間名, "60標本の定常"),
        (intervals::局所可視性の区間一覧[0], "60標本の定常"),
        (intervals::局所可視性の区間一覧[1], "60標本の定常"),
        (intervals::初回だけの区間名, "起動後1回の単発"),
    ];
    let 行一覧: Vec<String> = 区間一覧
        .iter()
        .map(|(区間名, 標本の別)| 区間1つの食い違い(停止a, 停止a2, 区間名, 標本の別))
        .collect();
    format!("停止Aと停止A'の食い違い(区間別): {}", 行一覧.join(" / "))
}

/// 区間1つぶんの食い違い。標本の別を添えるのは、単発の区間と60標本の定常区間で数の意味が違うためである。単発の値は窓の分位でなく1回の実測そのものであり、機材の揺れの大きさを語る根拠にならない。
fn 区間1つの食い違い(停止a: &一標本, 停止a2: &一標本, 区間名: &str, 標本の別: &str) -> String {
    let (Some(前), Some(後)) = (停止a.区間を参照する(区間名), 停止a2.区間を参照する(区間名)) else {
        return format!("{区間名}は行が片方に無いため測れない");
    };
    let 割合 = 相対差(前.第50百分位ミリ秒, 後.第50百分位ミリ秒);
    let 見立て = if 割合 > 交絡を告げる割合 {
        "機材が動いた"
    } else {
        "落ち着いている"
    };
    format!(
        "{区間名}[{標本の別}]{:.4}msと{:.4}msで{:.1}パーセント({見立て})",
        前.第50百分位ミリ秒,
        後.第50百分位ミリ秒,
        割合 * 100.0
    )
}

/// 大きい側を分母に取る相対差。どちらを基準にしても同じ値になり、どちらが速かったかに読み手が引きずられない。
fn 相対差(前: f64, 後: f64) -> f64 {
    let 分母 = 前.abs().max(後.abs());
    if 分母 <= 0.0 {
        return 0.0;
    }
    (前 - 後).abs() / 分母
}
