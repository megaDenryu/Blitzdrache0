//! 標本を人が読める表にする工程。受け取るのは全標本、出すのは標準出力への行だけである。判定は行わない。
//!
//! 区間別の行に加えて導出の2行を出すのは、計測の正本が全更新合計と更新なし定常値を別に求めるためである
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」)。
//!
//! 注意: 生成の合計は分位の和であり、和の分位ではない。フレームごとの合計を保つ計器を持たないため、
//! 予算と突き合わせる目安として読む(同じ断りが`shadow_gpu_time`の距離区分の合計にも付いている)。

use super::intervals;
use super::record::一標本;

pub(super) fn 表示する(標本一覧: &[一標本]) {
    println!();
    println!("条件 / 区間 / 平均 / p50 / p95 / 標本数 (ミリ秒)");
    for 標本 in 標本一覧 {
        for (区間名, 分布) in intervals::全区間一覧().iter().zip(&標本.区間別) {
            println!(
                "  {} / {区間名} / {:.4} / {:.4} / {:.4} / {}",
                標本.条件名, 分布.平均ミリ秒, 分布.p50ミリ秒, 分布.p95ミリ秒, 分布.標本数
            );
        }
        let 合計 = 標本.生成の合計();
        println!(
            "  {} / 生成の合計 / {:.4} / {:.4} / {:.4} / {}",
            標本.条件名, 合計.平均ミリ秒, 合計.p50ミリ秒, 合計.p95ミリ秒, 合計.標本数
        );
    }
    println!("条件 / 数えたフレーム数 / 焼き直したフレーム数 / 積んだ生成パスの総数 / 1フレームの見込み(初回・焼き直し)");
    for 標本 in 標本一覧 {
        println!(
            "  {} / {} / {} / {} / {}・{}",
            標本.条件名,
            標本.焼き上げ.数えたフレーム数,
            標本.焼き上げ.焼き直したフレーム数,
            標本.焼き上げ.総数,
            標本.見込み.初回の合計,
            標本.見込み.焼き直しの合計
        );
    }
}

/// 全更新合計。毎フレーム焼く条件の生成4区間の分位の和である。
pub(super) fn 全更新合計の行(進行b: &一標本) -> String {
    let 合計 = 進行b.生成の合計();
    format!(
        "全更新合計(進行B・生成{}区間の分位の和・鏡面は{}段の合計): p50 {:.4}ms・p95 {:.4}ms",
        intervals::生成の区間一覧.len(),
        鏡面の段数(進行b),
        合計.p50ミリ秒,
        合計.p95ミリ秒
    )
}

/// 更新なし定常。生成が1本も積まれないフレームで間接光に費やされるのは消費の区間だけである。
///
/// 注意: 停止Aの生成区間の行は、初回のフレームで焼いた最後の標本が窓に残っているだけであり、毎フレームの費用ではない。
/// 標本数が1件であることがその見分けになる。
pub(super) fn 更新なし定常の行(停止a: &一標本) -> String {
    let 消費 = intervals::消費の区間名;
    let Some(分布) = 停止a.区間を参照する(消費) else {
        return format!("更新なし定常(停止A): {消費}の行が無い");
    };
    format!(
        "更新なし定常(停止A・生成は1本も積まれず{消費}だけが走る): p50 {:.4}ms・p95 {:.4}ms",
        分布.p50ミリ秒, 分布.p95ミリ秒
    )
}

/// 反射率積分表は起動後の1フレームだけが焼くため、分位でなく単発の実測値として3実行ぶんを並べる。
pub(super) fn 反射率積分表の行(標本一覧: &[一標本]) -> String {
    let 区間名 = intervals::初回だけの区間名;
    let 並び: Vec<String> = 標本一覧
        .iter()
        .map(|標本| match 標本.区間を参照する(区間名) {
            Some(分布) => format!("{}{:.4}ms(標本{})", 標本.条件名, 分布.平均ミリ秒, 分布.標本数),
            None => format!("{}なし", 標本.条件名),
        })
        .collect();
    format!("{区間名}(初回の1フレームだけの単発値): {}", 並び.join("・"))
}

/// 焼き直し1フレームぶんの見込みの本数から、鏡面畳込みが焼く段の数を求める。遠方環境・最詳細段の複製・拡散照度の
/// 3本を除いた残りが段の数である。本番の`焼き上げの計画`が答えた本数から導くため、段数の台帳を検収側に持たない。
fn 鏡面の段数(標本: &一標本) -> u64 {
    標本.見込み.焼き直しの合計.saturating_sub(3)
}
