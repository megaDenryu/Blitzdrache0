//! 条件ごとの区間別の値と焼き上げの本数を、人が読める表として標準出力へ書く工程。
//! 受け取るのは全標本、返すものは無い。
//! 判定は行わず、成功の報告へ載せる導出の行は`summary`が組む。
//!
//! 表に並ぶ「間接照明生成の合計」は、計器がフレーム内で5つの生成区間を足して作った合成区間である。
//! 全更新合計はこの行の分位で語る。
//! 並べて出す「区間別分位の和(参考値)」は内訳の分位を足しただけの値であり、分位の加法性が一般に成立しないため公式の全更新合計として読んではならない。
//! 内訳のどれが合計を押し上げているかを読む助けに置く。

use super::intervals;
use super::record::一標本;

pub(super) fn 表示する(標本一覧: &[一標本]) {
    println!();
    println!("条件 / 区間 / 平均 / p50 / p95 / 標本数 (ミリ秒)");
    for 標本 in 標本一覧 {
        for (区間名, 分布) in intervals::全区間一覧().iter().zip(&標本.区間別) {
            println!(
                "  {} / {区間名} / {:.4} / {:.4} / {:.4} / {}",
                標本.条件名, 分布.平均ミリ秒, 分布.p50ミリ秒, 分布.p95ミリ秒, 分布.標本数
            );
        }
        let 参考 = 標本.区間別分位の和();
        println!(
            "  {} / 区間別分位の和(参考値) / {:.4} / {:.4} / {:.4} / {}",
            標本.条件名, 参考.平均ミリ秒, 参考.p50ミリ秒, 参考.p95ミリ秒, 参考.標本数
        );
    }
    println!("条件 / 数えたフレーム数 / 焼き直したフレーム数 / 積んだ生成パスの総数 / 1フレームの見込み(初回・焼き直し)");
    for 標本 in 標本一覧 {
        println!(
            "  {} / {} / {} / {} / {}・{}",
            標本.条件名,
            標本.焼き上げ.数えたフレーム数,
            標本.焼き上げ.焼き直したフレーム数,
            標本.焼き上げ.総数,
            標本.見込み.初回の合計,
            標本.見込み.焼き直しの合計
        );
    }
}
