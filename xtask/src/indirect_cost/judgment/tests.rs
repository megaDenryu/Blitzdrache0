//! 判定の反証。担当するのは、この入口が本当に落とすべき実行を落とすことを示すことである。
//!
//! 本数の期待そのもの(初回の合計と焼き直しの合計から総数を組む式)は`sky-lut`側の反証が持つ。
//! ここが見るのはこの入口の配線、すなわち時計の止め方から焼き方への写しと、3実行の見込みが揃うことの確認である。

use crate::sky_lut::indirect_pass_count::rows::{実測, 見込み};

use super::super::record::{一標本, 区間の分布};
use super::super::schedule::時計;
use super::*;

const 見込みの正例: 見込み = 見込み {
    初回の合計: 9,
    焼き直しの合計: 8,
};

fn 標本(条件名: &'static str, 焼き直したフレーム数: u64, 総数: u64) -> 一標本 {
    一標本 {
        実行番号: 0,
        条件名,
        // 焼き直したフレーム数から1を引いた回数だけ区間が変わった実行として組む。
        区間の変化回数: 焼き直したフレーム数 - 1,
        区間別: vec![
            区間の分布 {
                平均ミリ秒: 1.0,
                第50百分位ミリ秒: 1.0,
                第95百分位ミリ秒: 1.0,
                標本数: 60,
            };
            intervals::全区間一覧().len()
        ],
        焼き上げ: 実測 {
            数えたフレーム数: 160,
            焼き直したフレーム数,
            総数,
        },
        見込み: 見込みの正例,
    }
}

/// 停止は初回の1フレームだけが9本、進行は区間が159回変わって160フレームが9+8×159=1281本を焼く。
fn 正例() -> (Vec<一標本>, Vec<時計>) {
    let 標本一覧 = vec![標本("停止A", 1, 9), 標本("進行B", 160, 1281), 標本("停止A2", 1, 9)];
    (標本一覧, vec![時計::停止, 時計::進行, 時計::停止])
}

#[test]
fn 計画どおりの三実行は通る() {
    let (標本一覧, 時計一覧) = 正例();
    assert!(本数が計画どおりであることを確かめる(&標本一覧, &時計一覧).is_ok());
}

/// 時計を止めたはずの実行が毎フレーム焼いていたら落とす。この取り違えは更新なし定常の値を別の状態の値にする。
#[test]
fn 停止のはずが毎フレーム焼いていたら落とす() {
    let (mut 標本一覧, 時計一覧) = 正例();
    標本一覧[0] = 標本("停止A", 160, 1281);
    assert!(本数が計画どおりであることを確かめる(&標本一覧, &時計一覧).is_err());
}

/// 時計を進めたはずの実行が初回しか焼いていなかったら落とす。全更新合計が初回1フレームの値になる。
#[test]
fn 進行のはずが初回しか焼いていなかったら落とす() {
    let (mut 標本一覧, 時計一覧) = 正例();
    標本一覧[1] = 標本("進行B", 1, 9);
    assert!(本数が計画どおりであることを確かめる(&標本一覧, &時計一覧).is_err());
}

/// 区間の変化回数と焼き直したフレーム数が食い違えば落とす。間引きが効かず区間の中でも焼いている状態がこれである。
#[test]
fn 区間の変化回数と焼き直したフレーム数が食い違えば落とす() {
    let (mut 標本一覧, 時計一覧) = 正例();
    標本一覧[1].区間の変化回数 = 100;
    assert!(本数が計画どおりであることを確かめる(&標本一覧, &時計一覧).is_err());
}

#[test]
fn 見込みが実行ごとに違えば落とす() {
    let (mut 標本一覧, 時計一覧) = 正例();
    標本一覧[2].見込み = 見込み {
        初回の合計: 8,
        焼き直しの合計: 7,
    };
    assert!(本数が計画どおりであることを確かめる(&標本一覧, &時計一覧).is_err());
}

#[test]
fn 有限でない値を落とす() {
    let mut 標本一覧 = vec![標本("停止A", 1, 9)];
    標本一覧[0].区間別[0].第95百分位ミリ秒 = f64::INFINITY;
    assert!(値が有限であることを確かめる(&標本一覧).is_err());
}
