//! 子プロセスの標準出力から1標本ぶんの値を取り出す工程。
//! 受け取るのは標準出力と実行番号と条件名、返すのは区間ごとの分布と焼き上げの本数を持つ標本である。
//!
//! GPU時間の行の綴りは`crates/blitz_app/src/reports/gpu_time_table.rs`の出力と一致させている。
//! 「平均 (p50 X / p95 Y / 標本N)」の形であり、平均は区切りの次の1語、他はそれぞれの鍵の次の1語である。
//! 焼き上げの本数の行は`sky-lut`と同じ読み手を使う(同じ綴りを2箇所で持たないため)。
//!
//! 区間が1つでも欠けていたら失敗にする。
//! この世界が遠方環境の契約を選んでいないか、パス名が変わったことを意味しており、値が採れないまま表だけが出る事態を避ける。

use crate::sky_lut::indirect_pass_count::rows;

use super::intervals;
use super::record::{一標本, 区間の分布};

pub(super) fn 標本を取り出す(標準出力: &str, 実行番号: usize, 条件名: &'static str) -> Result<一標本, String> {
    let mut 区間別 = Vec::new();
    for 区間名 in intervals::全区間一覧() {
        区間別.push(区間を読む(標準出力, 区間名, 条件名)?);
    }
    Ok(一標本 {
        実行番号,
        条件名,
        区間別,
        焼き上げ: rows::実測を読む(標準出力, 条件名)?,
        見込み: rows::見込みを読む(標準出力, 条件名)?,
        区間の変化回数: rows::区間の変化回数を読む(標準出力, 条件名)?,
    })
}

fn 区間を読む(標準出力: &str, 区間名: &str, 条件名: &str) -> Result<区間の分布, String> {
    let 鍵 = format!("  {区間名}: ");
    let 行 = 標準出力
        .lines()
        .find(|行| 行.starts_with(&鍵))
        .ok_or_else(|| format!("{条件名}のパス別GPU時間の表に区間{区間名}が無い"))?;
    Ok(区間の分布 {
        平均ミリ秒: 鍵の次の小数(行, &鍵, 区間名)?,
        p50ミリ秒: 鍵の次の小数(行, "p50 ", 区間名)?,
        p95ミリ秒: 鍵の次の小数(行, "p95 ", 区間名)?,
        標本数: 鍵の次の語(行, "標本", 区間名)?
            .trim_end_matches(')')
            .parse()
            .map_err(|誤り| format!("区間{区間名}の標本数を数として読めない: {誤り}"))?,
    })
}

fn 鍵の次の小数(行: &str, 鍵: &str, 区間名: &str) -> Result<f64, String> {
    let 語 = 鍵の次の語(行, 鍵, 区間名)?;
    語.parse().map_err(|誤り| format!("区間{区間名}の値を数として読めない({語}): {誤り}"))
}

fn 鍵の次の語<'行>(行: &'行 str, 鍵: &str, 区間名: &str) -> Result<&'行 str, String> {
    let 残り = 行
        .split_once(鍵)
        .map(|(_, 残り)| 残り)
        .ok_or_else(|| format!("区間{区間名}の行に鍵{鍵}が無い: {行}"))?;
    残り
        .split_whitespace()
        .next()
        .ok_or_else(|| format!("区間{区間名}の鍵{鍵}の次に値が無い"))
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    const 標本: &str = "パス別GPU時間(直近60フレームの窓):\n  遠方環境用スカイビュー生成: 0.0200 (p50 0.0210 / p95 0.0220 / 標本60)\n  遠方環境生成: 0.1000 (p50 0.1100 / p95 0.1200 / 標本60)\n  鏡面畳込み最詳細段の複製: 0.0100 (p50 0.0110 / p95 0.0120 / 標本60)\n  拡散照度生成: 0.2000 (p50 0.2100 / p95 0.2200 / 標本60)\n  鏡面畳込み生成: 0.3000 (p50 0.3100 / p95 0.3200 / 標本60)\n  間接照明生成の合計: 0.6100 (p50 0.6000 / p95 0.7000 / 標本60)\n  シーン描画: 1.0000 (p50 1.0100 / p95 1.0200 / 標本60)\n  反射率積分表生成: 0.0500 (p50 0.0500 / p95 0.0500 / 標本1)\n間接照明生成パス数 数えたフレーム数=160 焼き直したフレーム数=160 総数=1281\n間接照明生成パス数の見込み 契約=遠方環境 初回の合計=9 焼き直しの合計=8\n太陽天頂区間 提示へ到達したフレーム数=160 区間が変わった回数=159 直近の区間識別=42\n";

    #[test]
    fn 八区間と焼き上げの本数を読む() {
        let 標本値 = 標本を取り出す(標本, 0, "進行B").unwrap();
        assert_eq!(標本値.区間別.len(), 8);
        let 鏡面 = 標本値.区間を参照する("鏡面畳込み生成").unwrap();
        assert!((鏡面.p95ミリ秒 - 0.32).abs() < 1.0e-9, "{}", 鏡面.p95ミリ秒);
        assert_eq!(標本値.区間を参照する("反射率積分表生成").unwrap().標本数, 1);
        assert_eq!(標本値.焼き上げ.総数, 1281);
        assert_eq!(標本値.見込み.焼き直しの合計, 8);
    }

    /// 合成区間の分位は、内訳の分位を足した参考値と別の値である。分位の加法性が成立しないことがこの差に出ている。
    #[test]
    fn 合成区間の分位は区間別分位の和と別の値である() {
        let 標本値 = 標本を取り出す(標本, 0, "進行B").unwrap();
        let 合成 = 標本値.区間を参照する("間接照明生成の合計").unwrap();
        let 参考 = 標本値.区間別分位の和();
        assert!((合成.p50ミリ秒 - 0.60).abs() < 1.0e-9, "{}", 合成.p50ミリ秒);
        assert!((参考.p50ミリ秒 - 0.662).abs() < 1.0e-9, "{}", 参考.p50ミリ秒);
        assert_eq!(参考.標本数, 60);
    }

    #[test]
    fn 区間が欠けたら落とす() {
        assert!(標本を取り出す("パス別GPU時間:\n  シーン描画: 1.0000 (p50 1.0 / p95 1.0 / 標本60)\n", 0, "停止A").is_err());
    }
}
