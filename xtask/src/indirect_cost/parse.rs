//! 子プロセスの終了時報告から1標本ぶんの値を取り出す工程。
//! 受け取るのは終了時報告と実行番号と条件名、返すのは区間ごとの分布と焼き上げの本数を持つ標本である。
//!
//! GPU時間の行の綴りは`crates/blitz_app/src/reports/gpu_time_table.rs`の出力と一致させている。
//! 「平均 (p50 X / p95 Y / 標本N)」の形であり、平均は区間名の鍵の次の1語、分位は開き括弧が触れた鍵の次の1語、
//! 標本数は鍵に続く残りである。
//! 焼き上げの本数の行は`sky-lut`と同じ読み手を使う(同じ綴りを2箇所で持たないため)。
//!
//! 区間が1つでも欠けていたら失敗にする。この世界が遠方環境の契約を選んでいないか、パス名が変わったことを意味しており、値が採れないまま表だけが出る事態を避ける。

#[cfg(test)]
mod sample_tests;

use crate::acceptance::{報告の区画, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};
use crate::sky_lut::indirect_pass_count::rows;

use super::intervals;
use super::record::{一標本, 区間の分布};

const 表の見出し: 報告の見出し = 報告の見出し::定数から生成する("パス別GPU時間");
/// 分位の鍵。分布の行では開き括弧が鍵へ触れているため、末尾一致で探す。
const 中央値の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("p50");
const 第95百分位の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("p95");
/// 標本数は「標本60)」の形で1語に続くため、鍵の後ろの残りから閉じ括弧を落として読む。
///
/// 注意: 区間名そのものが「標本」を含む(「局所可視性の遮蔽の標本化」)。鍵で始まる語を探す形にすることで、
/// 名前の中の「標本」を値の位置と読まずに済む。
const 標本数の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("標本");

pub(super) fn 標本を取り出す(報告: &終了時報告, 実行番号: usize, 条件名: &'static str) -> Result<一標本, 検収エラー> {
    let 表 = 報告.見出しの区画(表の見出し)?;
    let mut 区間別 = Vec::new();
    for 区間名 in intervals::全区間一覧() {
        区間別.push(区間を読む(&表, 区間名)?);
    }
    Ok(一標本 {
        実行番号,
        条件名,
        区間別,
        焼き上げ: rows::実測を読む(報告)?,
        見込み: rows::見込みを読む(報告, 条件名)?,
        区間の変化回数: rows::区間の変化回数を読む(報告)?,
    })
}

fn 区間を読む(表: &報告の区画, 区間名: &str) -> Result<区間の分布, 検収エラー> {
    let 接頭辞 = 報告の見出し::組み立てた綴りから生成する(format!("{区間名}:"));
    let 行 = 表.接頭辞の行(&接頭辞)?;
    let 平均の鍵 = 報告の行の鍵::組み立てた綴りから生成する(format!("{区間名}:"));
    Ok(区間の分布 {
        平均ミリ秒: 行.鍵に結ばれた数(&平均の鍵, 鍵に値が結ばれる形::次の語が値である)?,
        第50百分位ミリ秒: 行.鍵に結ばれた数(&中央値の鍵, 鍵に値が結ばれる形::この綴りで終わる語の次が値である)?,
        第95百分位ミリ秒: 行.鍵に結ばれた数(&第95百分位の鍵, 鍵に値が結ばれる形::この綴りで終わる語の次が値である)?,
        標本数: 行.鍵に結ばれた語から数字だけを読む(&標本数の鍵, 鍵に値が結ばれる形::この綴りに続く残りが値である)?,
    })
}
