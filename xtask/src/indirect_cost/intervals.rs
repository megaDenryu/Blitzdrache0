//! 計測するGPU計器の区間の一覧。
//! 担当するのは「どのパス名を何の役割の区間として読むか」だけである。
//! 名前はレンダーグラフのパス名そのままであり、正本は積む側(`crates/blitz_render/src/vulkan/distant_environment/pass.rs`と`crates/blitz_render/src/vulkan/derived_environment/pass.rs`と`.../frame/record/scene_pass.rs`)にある。
//!
//! 鏡面畳込み生成は粗さの段ごとにパスを積むが、計器がフレーム内の同名の回を足して1標本にするため、この1つの区間名で全縮小段の合計が読める(参照: `crates/blitz_render/src/vulkan/gpu_timing/readback.rs`)。

/// 遠方環境キーが変わったフレームだけ走る生成の区間。
/// 並びは本番のレンダーグラフが積む宣言順である。
pub(super) const 生成の区間一覧: [&str; 5] = [
    "遠方環境用スカイビュー生成",
    "遠方環境生成",
    "鏡面畳込み最詳細段の複製",
    "拡散照度生成",
    "鏡面畳込み生成",
];

/// 上の5区間をフレーム内で足した合成の区間。
/// **全更新合計はこの区間の分位で語る**。
/// 分位の加法性は一般に成立しないため、5区間それぞれの分位を足した値は1フレームの生成合計の分位ではない。
/// 合成の標本を作るのは計器側であり、正本は`crates/blitz_render/src/vulkan/indirect_lighting/generation_interval.rs`にある。
pub(super) const 生成の合計の区間名: &str = "間接照明生成の合計";

/// 間接光を消費する区間。
/// 遠方環境の契約を選んだ世界では、この世界のシーン描画そのものが消費である。
/// 間接光だけを取り出した値ではないため、定数近似の世界との差でしか消費の増分は語れない。
pub(super) const 消費の区間名: &str = "シーン描画";

/// 起動後の1フレームだけが焼く区間。窓へ入る標本が1件しかないため、分位でなく単発の実測値として読む。
pub(super) const 初回だけの区間名: &str = "反射率積分表生成";

/// 報告と生値に並べる全区間。
/// 生成の内訳・生成の合計・消費・初回だけをこの順で並べる。
/// **先頭が生成の内訳である並びを保つ**。
/// `record::一標本::区間別分位の和`がこの前提で先頭を数え取る。
pub(super) fn 全区間一覧() -> Vec<&'static str> {
    let mut 一覧: Vec<&'static str> = 生成の区間一覧.to_vec();
    一覧.push(生成の合計の区間名);
    一覧.push(消費の区間名);
    一覧.push(初回だけの区間名);
    一覧
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 先頭が生成の内訳であることを含めて反証する。この並びが崩れると区間別分位の和が別の区間を足す。
    #[test]
    fn 全区間は生成と消費と初回を重複なく並べる() {
        let 一覧 = 全区間一覧();
        assert_eq!(一覧.len(), 生成の区間一覧.len() + 3);
        assert_eq!(&一覧[..生成の区間一覧.len()], 生成の区間一覧.as_slice());
        assert_eq!(一覧[生成の区間一覧.len()], 生成の合計の区間名);
        let mut 並べ替え = 一覧.clone();
        並べ替え.sort_unstable();
        並べ替え.dedup();
        assert_eq!(並べ替え.len(), 一覧.len(), "区間名が重複している: {一覧:?}");
    }
}
