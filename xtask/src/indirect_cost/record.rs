//! 1回の実行から採れた値と、全標本の生値ファイルへの書き出し。担当するのは値の形と、順序を落とさずに残すことである。
//!
//! 生値を残すのは、表に出す代表値だけでは「どの順番で採った値か」が失われるためである。
//! 停止Aと停止A'の食い違いを後から疑うには、実行番号と条件名を付けた1行1区間の並びが要る。
//!
//! 注意: 1行が持つのは1実行ぶんの窓の集約(平均・p50・p95・標本数)であり、フレーム1枚ごとの値ではない。
//! 計器が外へ出すのは窓の集約だけであり、フレーム別の列を持たないためである。
//! フレーム別の証拠が要るときは、同じディレクトリに残る実行ごとの標準出力(`run_<番号>_<条件>.log`)が唯一の記録になる。

use std::path::Path;

use super::intervals;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 区間の分布 {
    pub(super) 平均ミリ秒: f64,
    pub(super) p50ミリ秒: f64,
    pub(super) p95ミリ秒: f64,
    /// その区間の窓に入っている標本の件数。生成の区間では「そのぶんのフレームが焼いた」ことを意味する。
    pub(super) 標本数: u64,
}

pub(super) struct 一標本 {
    /// 起動した順の通し番号。0から始まり、交互の並びがそのまま並ぶ。
    pub(super) 実行番号: usize,
    pub(super) 条件名: &'static str,
    /// 添字が`intervals::全区間一覧`の添字である。
    pub(super) 区間別: Vec<区間の分布>,
    pub(super) 焼き上げ: crate::sky_lut::indirect_pass_count::rows::実測,
    pub(super) 見込み: crate::sky_lut::indirect_pass_count::rows::見込み,
    /// 太陽天頂区間が前のフレームから変わった回数。焼き直したフレーム数の期待をこの整数から立てる。
    pub(super) 区間の変化回数: u64,
}

impl 一標本 {
    pub(super) fn 区間を参照する(&self, 区間名: &str) -> Option<区間の分布> {
        let 添字 = intervals::全区間一覧().iter().position(|名前| *名前 == 区間名)?;
        self.区間別.get(添字).copied()
    }

    /// 生成の内訳5区間の分位を足した参考値。
    /// **和の分位ではなく分位の和であり、全更新合計として読んではならない**。
    /// 分位の加法性は一般に成立しないためであり、全更新合計は計器がフレーム内で足した`生成の合計の区間名`から読む。
    /// この行を残すのは、内訳のどれが合計を押し上げているかを読むときに、内訳と同じ足し方の値が並んでいると見やすいためである。
    ///
    /// 前提: `区間別`は`intervals::全区間一覧`と同じ並びであり、その先頭が生成の内訳である(`parse`が並びごと作る)。
    /// 名前で引き直さず先頭を数え取るのは、引けなかった区間を黙って飛ばして和を過小に見せる余地を作らないためである。
    pub(super) fn 区間別分位の和(&self) -> 区間の分布 {
        let mut 合計 = 区間の分布 {
            平均ミリ秒: 0.0,
            p50ミリ秒: 0.0,
            p95ミリ秒: 0.0,
            標本数: u64::MAX,
        };
        for 分布 in self.区間別.iter().take(intervals::生成の区間一覧.len()) {
            合計.平均ミリ秒 += 分布.平均ミリ秒;
            合計.p50ミリ秒 += 分布.p50ミリ秒;
            合計.p95ミリ秒 += 分布.p95ミリ秒;
            合計.標本数 = 合計.標本数.min(分布.標本数);
        }
        合計
    }
}

pub(super) fn 生値を書く(書き先: &Path, 標本一覧: &[一標本], 由来: &crate::release_build::構築の由来) -> Result<(), String> {
    let mut 本文: String = 由来
        .注記一覧()
        .iter()
        .map(|注記| {
            format!(
                "# {注記}
"
            )
        })
        .collect();
    本文.push_str("実行番号\t条件\t区間\t平均ミリ秒\tp50ミリ秒\tp95ミリ秒\t標本数\t焼き直したフレーム数\t数えたフレーム数\n");
    for 標本 in 標本一覧 {
        for (区間名, 分布) in intervals::全区間一覧().iter().zip(&標本.区間別) {
            本文.push_str(&行にする(標本, 区間名, *分布));
        }
        本文.push_str(&行にする(標本, "区間別分位の和(参考値)", 標本.区間別分位の和()));
    }
    std::fs::write(書き先, 本文).map_err(|誤り| format!("{}を書けなかった: {誤り}", 書き先.display()))
}

fn 行にする(標本: &一標本, 区間名: &str, 分布: 区間の分布) -> String {
    format!(
        "{}\t{}\t{区間名}\t{:.4}\t{:.4}\t{:.4}\t{}\t{}\t{}\n",
        標本.実行番号,
        標本.条件名,
        分布.平均ミリ秒,
        分布.p50ミリ秒,
        分布.p95ミリ秒,
        分布.標本数,
        標本.焼き上げ.焼き直したフレーム数,
        標本.焼き上げ.数えたフレーム数
    )
}
