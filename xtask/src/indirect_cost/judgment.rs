//! この入口が持つ機械判定。担当するのは「区間の値が数として成立しているか」と「積んだ生成パスの本数が
//! 本番の焼き上げの計画が答えた見込みどおりか」の2つである。
//!
//! 費用の合否は判定しない。
//! 予算との突き合わせはマイルストーンの定点で評価軸を更新するときに人が行うためであり、ここに上限を置くと同じ予算が2箇所に住むことになる(参照: `_doc/計画/評価軸.md`)。
//! validationの指摘0件は実行のたびに`run`が確かめており、この工程は数の側だけを見る。
//!
//! 停止Aと停止A'の食い違いを1文にする工程は`drift`が持つ。あれは合否を出さないため、判定とは別の場所に置く。

#[cfg(test)]
