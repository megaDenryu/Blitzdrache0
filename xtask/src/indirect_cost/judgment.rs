//! この入口が持つ機械判定。担当するのは「区間の値が数として成立しているか」だけである。
//!
//! 費用の合否は判定しない。予算との突き合わせはマイルストーンの定点で評価軸を更新するときに人が行うためであり、
//! ここに上限を置くと同じ予算が2箇所に住むことになる(参照: `_doc/計画/評価軸.md`)。
//! validationの指摘0件は実行のたびに`run`が確かめており、この工程は数の側だけを見る。

#[cfg(test)]
mod tests;

use crate::sky_lut::indirect_pass_count::{本数を確かめる, 焼き方};

use super::intervals;
use super::record::一標本;
use super::schedule::時計;

/// 停止Aと停止A'の食い違いがこの割合を超えたら、条件の差でなく機材の状態が動いたものとして報告に明示する。
/// 判定には使わない。シャドウの律速切り分けでは同じ条件のあいだで合計が3.13ミリ秒から4.31ミリ秒(38パーセント)まで
/// 動いており、その規模を読み手が見落とさない位置に線を引いている。
const 交絡を告げる割合: f64 = 0.10;

pub(super) fn 値が有限であることを確かめる(標本一覧: &[一標本]) -> Result<(), String> {
    for 標本 in 標本一覧 {
        for (区間名, 分布) in intervals::全区間一覧().iter().zip(&標本.区間別) {
            for (量の名前, 値) in [("平均", 分布.平均ミリ秒), ("p50", 分布.p50ミリ秒), ("p95", 分布.p95ミリ秒)] {
                if !値.is_finite() {
                    return Err(format!("{}の区間{区間名}の{量の名前}が有限でない({値})", 標本.条件名));
                }
            }
        }
    }
    Ok(())
}

/// 3実行とも、積んだ生成パスの本数が本番の焼き上げの計画が答えた見込みどおりであることを確かめる。
///
/// 費用の判定ではなく、その実行が本当に測るべきものを測ったかの判定である。時計を止めた条件が毎フレーム焼いていたり
/// 進めた条件が初回しか焼いていなかったりすれば、全更新合計も更新なし定常も別の状態の値になる。期待の組み立ては
/// `sky-lut`と同じ読み手が持つ(本数の期待を2箇所で組まないため)。
pub(super) fn 本数が計画どおりであることを確かめる(標本一覧: &[一標本], 時計一覧: &[時計]) -> Result<(), String> {
    let Some(基準) = 標本一覧.first().map(|標本| 標本.見込み) else {
        return Err("実行が1つも無いため本数を確かめられない".to_string());
    };
    for (標本, 時計) in 標本一覧.iter().zip(時計一覧) {
        // 見込みは同じ資源構成から導かれるため3実行で一致する。食い違ったら条件ごとに別の粗さ段数が立っている。
        if 標本.見込み != 基準 {
            return Err(format!("{}の見込み{:?}が停止Aの見込み{基準:?}と違う", 標本.条件名, 標本.見込み));
        }
        let 焼き方 = match 時計 {
            時計::停止 => 焼き方::初回だけ,
            時計::進行 => 焼き方::毎フレーム,
        };
        本数を確かめる(標本.焼き上げ, 標本.見込み, 標本.条件名, 焼き方)?;
    }
    Ok(())
}

/// 停止Aと停止A'のシーン描画のp50の食い違いを1文にする。同じ条件どうしの比較であるため、ここに出る差は
/// 条件の差ではなく機材の状態の移り変わりである。
pub(super) fn 交互実行の食い違い(停止a: &一標本, 停止a2: &一標本) -> String {
    let 消費 = intervals::消費の区間名;
    let (Some(前), Some(後)) = (停止a.区間を参照する(消費), 停止a2.区間を参照する(消費)) else {
        return format!("停止Aと停止A'の食い違い: {消費}の行が片方に無いため測れない");
    };
    let 割合 = 相対差(前.p50ミリ秒, 後.p50ミリ秒);
    let 見立て = if 割合 > 交絡を告げる割合 {
        "機材の状態が動いた(条件の差として読んではならない)"
    } else {
        "機材の状態は落ち着いている"
    };
    format!(
        "停止Aと停止A'の食い違い: {消費}のp50が{:.4}msと{:.4}msで相対差{:.1}パーセント({見立て})",
        前.p50ミリ秒,
        後.p50ミリ秒,
        割合 * 100.0
    )
}

/// 大きい側を分母に取る相対差。どちらを基準にしても同じ値になり、どちらが速かったかに読み手が引きずられない。
fn 相対差(前: f64, 後: f64) -> f64 {
    let 分母 = 前.abs().max(後.abs());
    if 分母 <= 0.0 {
        return 0.0;
    }
    (前 - 後).abs() / 分母
}
