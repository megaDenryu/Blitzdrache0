const 計測できた実行: 判定の名前 = 判定の名前::定数から生成する("本数を確かめる材料になる実行");

pub(super) fn 値が有限であることを確かめる(標本一覧: &[一標本]) -> Result<(), 判定の破れ> {
    for 標本 in 標本一覧 {
        for (区間名, 分布) in intervals::全区間一覧().iter().zip(&標本.区間別) {
            for (量の名前, 値) in [("平均", 分布.平均ミリ秒), ("p50", 分布.第50百分位ミリ秒), ("p95", 分布.第95百分位ミリ秒)]
            {
                量の判定名(標本.条件名, 区間名, 量の名前).有限であることを課す(値)?;
            }
        }
    }
    Ok(())
}

/// 3実行とも、積んだ生成パスの本数が本番の焼き上げの計画が答えた見込みどおりであることを確かめる。
///
/// 費用の判定ではなく、その実行が本当に測るべきものを測ったかの判定である。
/// 時計を止めた条件が毎フレーム焼いていたり進めた条件が初回しか焼いていなかったりすれば、全更新合計も更新なし定常も別の状態の値になる。
/// 期待の組み立ては`sky-lut`と同じ読み手が持つ(本数の期待を2箇所で組まないため)。
pub(super) fn 本数が計画どおりであることを確かめる(
    標本一覧: &[一標本], 時計一覧: &[時計]
) -> Result<(), 判定の破れ> {
    let Some(基準) = 標本一覧.first().map(|標本| 標本.見込み) else {
        return Err(計測できた実行.あるはずのものが無い破れ());
    };
    for (標本, 時計) in 標本一覧.iter().zip(時計一覧) {
        // 見込みは同じ資源構成から導かれるため3実行で一致する。食い違ったら条件ごとに別の粗さ段数が立っている。
        見込みの判定名(標本.条件名).綴りの一致を課す(&format!("{:?}", 標本.見込み), &format!("{基準:?}"))?;
        let 焼き方 = match 時計 {
            時計::停止 => 焼き方::初回だけ,
            時計::進行 => 焼き方::区間が変わるたび,
        };
        本数を確かめる(標本.焼き上げ, 標本.見込み, 標本.条件名, 焼き方, 標本.区間の変化回数)?;
    }
    Ok(())
}

fn 量の判定名(条件名: &str, 区間名: &str, 量の名前: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}の区間{区間名}の{量の名前}"))
}

fn 見込みの判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(
        format!("{条件名}の見込み(停止Aの見込みと食い違うなら条件ごとに別の粗さ段数が立っている)"),
    )
}
