//! 成功の報告へ載せる導出の3行を組む工程。
//! 受け取るのは標本、返すのは文である。
//! 標準出力へは1行も書かない(条件ごとの表は`table`が書く)。
//! 計測の正本が全更新合計と更新なし定常値を別に求めるためこの3行がある(参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」)。

use std::path::Path;

use super::record::一標本;
use super::{drift, intervals};
use crate::acceptance::{判定の名前, 判定の破れ, 描画フレーム数};

/// 焼き直しのフレームに必ず積まれる、鏡面畳込み以外の生成パスの本数。遠方環境・最詳細段の複製・拡散照度の3本である。
const 鏡面以外の生成本数: u64 = 3;

/// 3実行そろっていることを見る判定。そろわないと停止Aと停止A'の対が組めず、機材の揺れを語れない。
const そろった実行の数: 判定の名前 = 判定の名前::定数から生成する("採れた実行の数");
/// 交互の並びが起動する実行の数。台帳は`schedule`が持ち、ここはその長さを読む。
const 交互の並びの実行数: usize = super::schedule::交互の並び.len();

/// 全更新合計。
/// 区間を跨いだフレームで、計器がフレーム内で生成5区間を足した合成区間の分位である。
/// 内訳の分位を足した値を使わないのは、分位の加法性が一般に成立しないためである。
pub(super) fn 全更新合計の行(進行b: &一標本) -> Result<String, 判定の破れ> {
    let 区間名 = intervals::生成の合計の区間名;
    let 合成区間 =
        判定の名前::組み立てた綴りから生成する(format!("進行Bの表の合成区間{区間名}(無いなら計器へ合成区間の宣言が渡っていない)"));
    let 合計 = 進行b.区間を参照する(区間名).ok_or_else(|| 合成区間.あるはずのものが無い破れ())?;
    Ok(format!(
        "全更新合計(進行B・計器がフレーム内で足した生成{}区間の合計の分位・鏡面は{}段の合計): p50 {:.4}ms・p95 {:.4}ms(標本{})",
        intervals::生成の区間一覧.len(),
        鏡面の段数(進行b)?,
        合計.p50ミリ秒,
        合計.p95ミリ秒,
        合計.標本数
    ))
}

/// 更新なし定常。生成が1本も積まれないフレームで間接光に費やされるのは消費の区間だけである。
///
/// 注意: 停止Aの生成区間の行は、初回のフレームで焼いた最後の標本が窓に残っているだけであり、毎フレームの費用ではない。
/// 標本数が1件であることがその見分けになる。
pub(super) fn 更新なし定常の行(停止a: &一標本) -> String {
    let 消費 = intervals::消費の区間名;
    let Some(分布) = 停止a.区間を参照する(消費) else {
        return format!("更新なし定常(停止A): {消費}の行が無い");
    };
    format!(
        "更新なし定常(停止A・生成は1本も積まれず{消費}だけが走る): p50 {:.4}ms・p95 {:.4}ms",
        分布.p50ミリ秒, 分布.p95ミリ秒
    )
}

/// 反射率積分表は起動後の1フレームだけが焼くため、分位でなく単発の実測値として3実行ぶんを並べる。
pub(super) fn 反射率積分表の行(標本一覧: &[一標本]) -> String {
    let 区間名 = intervals::初回だけの区間名;
    let 並び: Vec<String> = 標本一覧
        .iter()
        .map(|標本| match 標本.区間を参照する(区間名) {
            Some(分布) => format!("{}{:.4}ms(標本{})", 標本.条件名, 分布.平均ミリ秒, 分布.標本数),
            None => format!("{}なし", 標本.条件名),
        })
        .collect();
    format!("{区間名}(初回の1フレームだけの単発値): {}", 並び.join("・"))
}

/// 焼き直し1フレームぶんの見込みの本数から、鏡面畳込みが焼く段の数を求める。
/// 本番の`焼き上げの計画`が答えた本数から導くため、段数の台帳を検収側に持たない。
///
/// 3本に満たない見込みは、その3本が常に積まれるという構造と食い違う。
/// 0段へ丸めて報告を続けると、実測の側が何段を足した値なのかを誰も言えないまま数字だけが出るため、型付きの失敗にする。
fn 鏡面の段数(標本: &一標本) -> Result<u64, 判定の破れ> {
    let 焼き直し = 標本.見込み.焼き直しの合計;
    let 判定名 = 判定の名前::組み立てた綴りから生成する(format!(
        "{}の焼き直しの見込みの本数(鏡面以外の{鏡面以外の生成本数}本に満たないなら、常に積まれる3本という構造と食い違う)",
        標本.条件名
    ));
    判定名.下限を課す(焼き直し, 鏡面以外の生成本数)?;
    Ok(焼き直し - 鏡面以外の生成本数)
}

/// 3実行がそろっていることを前提にせず、そろっていなければ何が足りないかを言って失敗にする。
pub(super) fn 要約を組む(
    標本一覧: &[一標本],
    出力先: &Path,
    フレーム数: 描画フレーム数,
    由来: &crate::release_build::構築の由来,
) -> Result<String, 判定の破れ> {
    そろった実行の数.一致を課す(標本一覧.len(), 交互の並びの実行数)?;
    let (停止a, 進行b, 停止a2) = (&標本一覧[0], &標本一覧[1], &標本一覧[2]);
    Ok(format!(
        "1実行{}フレームの停止A・進行B・停止A'で、{}、{}、{}、{}。区間別の表と生値は{}にある。計測に使ったバイナリの由来は{}",
        フレーム数.枚数(),
        全更新合計の行(進行b)?,
        更新なし定常の行(停止a),
        反射率積分表の行(標本一覧),
        drift::交互実行の食い違い(停止a, 停止a2),
        出力先.display(),
        由来.一行にする()
    ))
}
