//! 1標本ぶんの読み取りを標本の報告で固定する検査。担当するのは「10区間ぶんの分布と焼き上げの本数を読めること」と
//! 「区間が1つでも欠けたら落とすこと」を標本で押さえることである。
//! 合成区間の分位と内訳の分位の和が別の値であることも、同じ標本で並べて示す。

#![allow(clippy::unwrap_used)]

use super::*;
use crate::acceptance::検収の実行名;

const 標本の実行名: 検収の実行名 = 検収の実行名::定数から生成する("indirect_cost_parse");

fn 報告にする(標準出力: &str) -> 終了時報告 {
    終了時報告::取り込む(&標本の実行名, 標準出力.to_string(), String::new())
}

const 標本: &str = "パス別GPU時間(直近60フレームの窓):\n  遠方環境用スカイビュー生成: 0.0200 (p50 0.0210 / p95 0.0220 / 標本60)\n  遠方環境生成: 0.1000 (p50 0.1100 / p95 0.1200 / 標本60)\n  鏡面畳込み最詳細段の複製: 0.0100 (p50 0.0110 / p95 0.0120 / 標本60)\n  拡散照度生成: 0.2000 (p50 0.2100 / p95 0.2200 / 標本60)\n  鏡面畳込み生成: 0.3000 (p50 0.3100 / p95 0.3200 / 標本60)\n  間接照明生成の合計: 0.6100 (p50 0.6000 / p95 0.7000 / 標本60)\n  シーン描画: 1.0000 (p50 1.0100 / p95 1.0200 / 標本60)\n  反射率積分表生成: 0.0500 (p50 0.0500 / p95 0.0500 / 標本1)
  局所可視性の遮蔽の標本化: 0.0900 (p50 0.0910 / p95 0.0920 / 標本60)
  局所可視性の両側ぼかし: 0.0600 (p50 0.0610 / p95 0.0620 / 標本60)\n間接照明生成パス数 数えたフレーム数=160 焼き直したフレーム数=160 総数=1281\n間接照明生成パス数の見込み 契約=遠方環境 初回の合計=9 焼き直しの合計=8\n太陽天頂区間 提示へ到達したフレーム数=160 区間が変わった回数=159 直近の区間識別=42\n";

#[test]
fn 十区間と焼き上げの本数を読む() {
    let 標本値 = 標本を取り出す(&報告にする(標本), 0, "進行B").unwrap();
    assert_eq!(標本値.区間別.len(), 10);
    assert_eq!(標本値.区間を参照する("局所可視性の両側ぼかし").unwrap().標本数, 60);
    let 鏡面 = 標本値.区間を参照する("鏡面畳込み生成").unwrap();
    assert!((鏡面.p95ミリ秒 - 0.32).abs() < 1.0e-9, "{}", 鏡面.p95ミリ秒);
    assert_eq!(標本値.区間を参照する("反射率積分表生成").unwrap().標本数, 1);
    assert_eq!(標本値.焼き上げ.総数, 1281);
    assert_eq!(標本値.見込み.焼き直しの合計, 8);
}

/// 合成区間の分位は、内訳の分位を足した参考値と別の値である。分位の加法性が成立しないことがこの差に出ている。
#[test]
fn 合成区間の分位は区間別分位の和と別の値である() {
    let 標本値 = 標本を取り出す(&報告にする(標本), 0, "進行B").unwrap();
    let 合成 = 標本値.区間を参照する("間接照明生成の合計").unwrap();
    let 参考 = 標本値.区間別分位の和();
    assert!((合成.p50ミリ秒 - 0.60).abs() < 1.0e-9, "{}", 合成.p50ミリ秒);
    assert!((参考.p50ミリ秒 - 0.662).abs() < 1.0e-9, "{}", 参考.p50ミリ秒);
    assert_eq!(参考.標本数, 60);
}

#[test]
fn 区間が欠けたら落とす() {
    let 一区間だけ = 報告にする("パス別GPU時間:\n  シーン描画: 1.0000 (p50 1.0 / p95 1.0 / 標本60)\n");
    assert!(標本を取り出す(&一区間だけ, 0, "停止A").is_err());
}
