//! どの条件をどの順で起動するかを決める工程。
//! 受け取るものは無く、返すのは起動する条件の並びである。
//! 1回ぶんの起動の中身は`run`が、引数から来る実行の指定は`plan`が持つ。
//!
//! 並びを時計停止A・時計進行B・時計停止A'に固定するのは、計測の正本がこの交互実行を要求するためである(参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」)。
//! AとA'は同じ条件であり、その食い違いは条件の差ではなく機材の状態の移り変わりの大きさを表す。
//! 同じ条件を続けて2回回すのでなく間に進行Bを挟むのは、Bが機材を温める側の条件であり、その前後でAを採ることで温まりによる押し上げがAの対で見えるためである。

use crate::acceptance::検収の実行名;

/// その実行で時計を進めるかどうか。進めると遠方環境キーが毎フレーム変わり、生成が毎フレーム走る。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 時計 {
    停止,
    進行,
}

/// `実行名`は型のまま持つ。実行時に組み立てて検証へ通す形にすると、使えない綴りが実機の起動まで見つからないためである。
pub(super) struct 実行条件 {
    pub(super) 実行名: 検収の実行名, // その実行を指す名前。書き出しと標準出力の記録のファイル名になるため、英数字と下線とハイフンだけを置ける
    pub(super) 呼び名: &'static str, // 人が読む呼び名。表と要約と生値の行と失敗の文面がこちらを出す
    pub(super) 時計: 時計,
}

pub(super) const 交互の並び: [実行条件; 3] = [
    実行条件 {
        実行名: 検収の実行名::定数から生成する("halt_a"),
        呼び名: "停止A",
        時計: 時計::停止,
    },
    実行条件 {
        実行名: 検収の実行名::定数から生成する("advance_b"),
        呼び名: "進行B",
        時計: 時計::進行,
    },
    実行条件 {
        実行名: 検収の実行名::定数から生成する("halt_a2"),
        呼び名: "停止A2",
        時計: 時計::停止,
    },
];

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 並びは停止と進行と停止である() {
        let 時計一覧: Vec<時計> = 交互の並び.iter().map(|条件| 条件.時計).collect();
        assert_eq!(時計一覧, vec![時計::停止, 時計::進行, 時計::停止]);
    }

    /// 停止の2実行は同じ条件でありながら別の名前を持つ。生値と表で採った順番を見分けるためである。
    #[test]
    fn 停止の二実行は別の名前を持つ() {
        assert_ne!(交互の並び[0].実行名, 交互の並び[2].実行名);
        assert_ne!(交互の並び[0].呼び名, 交互の並び[2].呼び名);
    }
}
