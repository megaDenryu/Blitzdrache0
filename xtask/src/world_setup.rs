//! 検収の世界の用意: 検証用アセットを焼く工程の成否を受け取り、その世界の実行時形式が実在するところまでを確かめる型。
//!
//! 世界ごとの入口がそれぞれ確認を書いていたのを1箇所へ集める。外部のアセットリポジトリが無い環境では、
//! 原型が1つも解決できずコンパイルが失敗する。失敗を見落として起動へ進むと、カタログ未登録という遠い場所の失敗に化けるため、
//! 焼いた直後に名指しして落とす。この確認が入口ごとに書かれていると、書き忘れた入口だけが遠い失敗を出す。
//!
//! 実行時形式のパスを型が私有するのは、役割を持つパスを裸の綴りで持ち回ると、確認する世界と焼いた世界が
//! 食い違っていても型が通るためである。ファイルの実在を見るのはこの型の中だけである。
//!
//! 置き場を綴りでなく`検証の出力の置き場名`で持つのは、検証の出力が載る木の名前をこの型が知らずに済ませるためである。
//! 木の名前を知っているのは`検証の出力ルート`だけであり、この型はその下のどこを見るかだけを持つ。
//! 破れうる前提の数え上げは`error`が持つ。

mod error;

use crate::verify::{検証の出力のファイル名, 検証の出力の置き場名, 検証の出力ルート};

pub use error::検収世界の用意の破れ;

pub struct 検収世界の用意 {
    世界の呼び名: &'static str,
    実行時形式の置き場: 検証の出力の置き場名,
    実行時形式のファイル名: 検証の出力のファイル名,
}

impl 検収世界の用意 {
    pub const fn 生成する(
        世界の呼び名: &'static str,
        実行時形式の置き場: 検証の出力の置き場名,
        実行時形式のファイル名: 検証の出力のファイル名,
    ) -> Self {
        Self {
            世界の呼び名,
            実行時形式の置き場,
            実行時形式のファイル名,
        }
    }

    /// 焼く工程が成功したことと、実行時形式が実在することの両方を確かめる。
    /// 成否を引数で受けるのは、どの世界をどの手順で焼くかを決めるのが呼び出し側だからである。
    pub fn 焼き上がりを確かめる(&self, 焼く工程が成功したか: bool) -> Result<(), 検収世界の用意の破れ> {
        if !焼く工程が成功したか {
            return Err(検収世界の用意の破れ::検証用アセットを生成できなかった {
                世界の呼び名: self.世界の呼び名,
            });
        }
        let 実行時形式のパス = 検証の出力ルート::既定().置き場の中のファイル(self.実行時形式の置き場, self.実行時形式のファイル名);
        if 実行時形式のパス.is_file() {
            return Ok(());
        }
        Err(検収世界の用意の破れ::実行時形式が作られていない {
            世界の呼び名: self.世界の呼び名,
            実行時形式のパス,
        })
    }
}
