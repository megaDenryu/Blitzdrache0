//! 部品で組んだ木の並びを焼いて実機で描き、木の姿を人が見るための絵を書き出す入口。
//!
//! **この入口の目的は、組み上がった木を判定できる大きさで写すことである。** 8km世界の散布の固定構図では
//! 1本の木が数画素にしかならず、幹の継ぎ目も枝の出方も葉房の付き方も絵から読み取れない。木の姿の合否は
//! 親エージェントの目視が確定する。
//!
//! 機械が見るのは、焼いた側が数えた勘定と走らせた側が出した計数が噛み合うことと、validationが0件であることだけである。
//! 期待値を検収の側へ定数で持たないのは、部品や規則を変えたときに検収だけが無言で通らなくなるためである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「段5の到達点」

mod error;
mod judgment;
mod run;

use std::path::PathBuf;
use std::process::ExitCode;

use error::木の並びの撮影エラー;

use super::tally_line::焼いた並びの勘定;
use crate::world_setup::検収世界の用意;

const 出力ディレクトリ: &str = "target/part_tree_row_draw";

/// 木の並びの実行時形式。この世界だけの出力ルートへ焼かれる。
///
/// 外部のアセットリポジトリが無い環境では、木の部品が1つも解決できずコンパイルが失敗する。失敗を見落として
/// 起動へ進むと、カタログ未登録という遠い場所の失敗に化けるため、焼いた直後に実在を確かめる。
const 検収世界: 検収世界の用意 =
    検収世界の用意::生成する("部品で組んだ木の並び", "target/part_tree_row_assets/prop_part_tree_row.blitzasset");

pub(super) fn 検収してコードへ変換する() -> ExitCode {
    match 検収する() {
        Ok(要約) => {
            println!("[xtask] part-tree-row-draw成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] part-tree-row-draw失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

/// 焼く前に前回の焼き上がりを消す。**この入口は焼く工程の報告の行を計数と突き合わせる期待値に使うため、
/// 生成台帳が据え置きを選ぶと行が1本も出ず、比べる相手を失う。** 消してよいのは、この置き場をこの入口だけが
/// 使うためである。まだ無いことは破れではない。
fn 前回の焼き上がりを消す() -> std::io::Result<()> {
    match std::fs::remove_dir_all(crate::compile_assets::部品で組んだ木の並びの出力ルート()) {
        Err(誤り) if 誤り.kind() == std::io::ErrorKind::NotFound => Ok(()),
        他 => 他,
    }
}

fn 検収する() -> Result<String, 木の並びの撮影エラー> {
    if !crate::gen_source_assets::検証用ソースアセットを生成して成否を返す() {
        return Err(木の並びの撮影エラー::ソースアセットを生成できなかった);
    }
    前回の焼き上がりを消す().map_err(木の並びの撮影エラー::前回の焼き上がりを消せなかった)?;
    let 標準出力 = crate::compile_assets::既定のソースから焼き標準出力を返す(
        crate::compile_assets::部品で組んだ木の並びの出力ルート(),
        crate::asset_generator::世界名::部品で組んだ木の並びの世界,
    )?;
    print!("{標準出力}");
    let 勘定 = 焼いた並びの勘定::標準出力から読む(標準出力)?;
    検収世界
        .焼き上がりを確かめる(true)
        .map_err(木の並びの撮影エラー::検収世界を用意できなかった)?;
    let 実行環境 = run::実行環境を作る(PathBuf::from(出力ディレクトリ))?;
    let 実行 = 実行環境.描いて読み戻す(run::木の並びの実行名, &run::起動指定を組み立てる())?;
    let 計数 = crate::report_parse::取り出す(実行.報告())?;
    let 絵 = 実行.書き出し先().目視用の絵へ変換する()?;
    judgment::焼いた側と走らせた側を突き合わせる(&勘定, &計数)?;
    Ok(format!(
        "木{}本を部品{}種類・材質スロット総和{}で組み、発行数{}・個体{}体。絵は{}",
        勘定.件数,
        勘定.部品の種類数,
        勘定.材質スロット数の総和,
        計数.シーン.発行数,
        計数.可視個体の選別.候補数,
        絵.display()
    ))
}
