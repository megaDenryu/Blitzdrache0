//! 部品で組んだ家の並びの検収エラーを人が読む1文へ写すトレイト実装。枝ごとに、どの前提がどう破れたかを出す。
//! 実装を型の定義と分けるのは、外部トレイトの実装が型自身の持ち物とは別の軸であるためである。

use std::fmt;

use super::部品で組んだ家の並びの検収エラー;

impl fmt::Display for 部品で組んだ家の並びの検収エラー {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::検収の器が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::判定が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::検収世界を用意できなかった(破れ) => write!(書き手, "{破れ}"),
            Self::アセットを焼けなかった(破れ) => write!(書き手, "{破れ}"),
            Self::ソースアセットを生成できなかった => {
                write!(書き手, "家並みの地面のソースアセットを生成できなかった")
            }
            Self::前回の焼き上がりを消せなかった(誤り) => {
                write!(書き手, "前回の焼き上がりを消せないため焼き直しを起こせない: {誤り}")
            }
        }
    }
}
