//! 規模1つぶんの起動の指定。受け取るのは規模、返すのは実行環境へ渡す起動指定である。
//! 起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! シーン名を`prop_part_house_row`にすることが、家並みの全体を収める初期カメラと、
//! 書き換えもピクセル判定も持たない検収計画を選ばせる。10軒と100軒は同じシーン名を持ち、読む出力ルートだけが違う。
//! 空は`--sky`で明示する。世界の方針が空ありになるのは名前が`terrain`で始まる世界だけであり、この世界はそこへ入らないためである。

use std::path::PathBuf;

use super::scale::家の並びの規模;
use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 描画フレーム数, 描画検収の実行環境, 検収エラー, 検収シーン名
};

const シーン名: 検収シーン名 = 検収シーン名::生成する("prop_part_house_row");
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(180);

/// 一日内時刻15時。太陽が斜めから当たり、軒ごとに違う向きの屋根面が明暗で見分けられる。
const 一日内秒: &str = "54000";

const 報告を出させる選択肢: [&str; 3] = ["--sky", "--report-draw-issue", "--report-memory"];

pub(super) fn 実行環境を作る(
    規模: 家の並びの規模, 出力ディレクトリ: PathBuf
) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        規模.実行時アセットルート(),
        出力ディレクトリ,
    )
}

pub(super) fn 起動指定を組み立てる() -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数)
        .値を持つ選択肢を足す("--time-of-day", 一日内秒)
        .選択肢をまとめて足す(&報告を出させる選択肢)
}
