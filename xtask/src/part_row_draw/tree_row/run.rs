//! 木の並び1回ぶんの起動の指定。受け取るのは書き出し先、返すのは実行環境と起動指定である。
//! 起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! シーン名を`prop_part_tree_row`にすることが、木を近くで写す初期カメラと、書き換えもピクセル判定も持たない
//! 検収計画を選ばせる。空は`--sky`で明示する。世界の方針が空ありになるのは名前が`terrain`で始まる世界だけであり、
//! この世界はそこへ入らないためである。
//!
//! 一日内時刻を15時にするのは、太陽が斜めから当たり、幹の丸みと葉房の塊が明暗で読み取れるためである。
//! 真上からの光では幹の円筒が一様に照らされ、節ごとの太さの違いが絵に出ない。

use std::path::PathBuf;

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収の実行名, 検収エラー, 検収シーン名,
};

const アセットルート: &str = "target/part_tree_row_assets";
const シーン名: 検収シーン名 = 検収シーン名::生成する("prop_part_tree_row");
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(180);

/// 書き出しの基準名。絵のファイル名になり、失敗の文面もこの名前で実行を名指す。
pub(super) const 木の並びの実行名: 検収の実行名 = 検収の実行名::定数から生成する("part_tree_row");

/// 一日内時刻15時。
const 一日内秒: &str = "54000";

const 報告を出させる選択肢: [&str; 3] = ["--sky", "--report-draw-issue", "--report-memory"];

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::綴りから生成する(アセットルート),
        出力ディレクトリ,
    )
}

pub(super) fn 起動指定を組み立てる() -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数)
        .値を持つ選択肢を足す("--time-of-day", 一日内秒)
        .選択肢をまとめて足す(&報告を出させる選択肢)
}
