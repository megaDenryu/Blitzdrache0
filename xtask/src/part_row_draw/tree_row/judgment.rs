//! 木の並びを焼いた側と走らせた側の突き合わせ。受け取るのは焼く工程の勘定と実機の計数、返すのは合否である。
//!
//! 期待値をどれも焼いた側の報告から採るのは、部品や規則を変えたときに検収だけが無言で通らなくなるためである。
//! この入口が持つ定数は「群でない描画対象は地面1つだけである」という世界の形だけであり、木の姿には触れない。
//!
//! **木が本当に部品から組み上がったかは、据えた部品の個体数が件数より多いことで見る。** 木1本が幹と枝と葉房の
//! 複数の個体になることがこの路線の要であり、1本が1個体のままなら展開が働いていない。何個体になるかは規則が
//! 決めるため、その数を検収の側へ書かない。

use crate::acceptance::{判定の名前, 判定の破れ};
use crate::part_row_draw::tally_line::焼いた並びの勘定;
use crate::report_parse::計数報告;

/// **発行数の期待値に最詳細段のプリミティブ数を使う前提は、全個体が最詳細段で描かれることである。**
/// この世界の構図は距離18メートルであり、個体別の詳細段の基準距離50メートルより手前に4本とも立つ。
/// 前提が破れて遠距離段の個体が混ざると、その段のプリミティブぶん発行が増えてこの判定が落ちる。
/// 黙って通ることはないため、前提を別の判定で確かめる必要は無い。
///
/// この世界が持つ群でない描画対象の数。地面1つだけである。描画発行はプリミティブごとに1回であり、
/// 地面は1つの材質しか持たないため、地面が立てる発行も1回である。
const 地面の描画対象の数: u64 = 1;

const 呼び名: &str = "部品で組んだ木の並び";

pub(super) fn 焼いた側と走らせた側を突き合わせる(
    勘定: &焼いた並びの勘定, 計数: &計数報告
) -> Result<(), 判定の破れ> {
    crate::count_consistency::計数の整合を検査する(呼び名, 計数)?;
    判定名("検証層の指摘").零件であることを課す(計数.validation件数)?;
    判定名("材質スロット数の総和(最詳細段のプリミティブの数と一致するはずである)")
        .一致を課す(勘定.材質スロット数の総和, 勘定.最詳細段のプリミティブ数の総和)?;
    判定名("群でない描画対象の数(地面1つだけのはずである)").一致を課す(群でない描画対象の数(計数), 地面の描画対象の数)?;
    判定名("シーンパスの発行数(地面の1と部品ごとの最詳細段のプリミティブ数の総和の和になるはずである)")
        .一致を課す(計数.シーン.発行数, 地面の描画対象の数 + 勘定.最詳細段のプリミティブ数の総和)?;
    判定名("可視判定へ登録された個体の候補数(焼く工程が据えた部品の個体数と一致するはずである)")
        .一致を課す(計数.可視個体の選別.候補数, 勘定.据えた部品の個体数)?;
    判定名("据えた部品の個体数(木1本が複数の部品へ展開されるはずである)").下限を課す(勘定.据えた部品の個体数, 勘定.件数 + 1)
}

/// 群でない描画対象の数。シーンパスの候補数と可視個体の選別の候補数の差であり、この世界では地面の1だけである。
fn 群でない描画対象の数(計数: &計数報告) -> u64 {
    計数.シーン.候補数.saturating_sub(計数.可視個体の選別.候補数)
}

fn 判定名(見るもの: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{呼び名}の{見るもの}"))
}
