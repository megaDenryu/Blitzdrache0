//! 件数を変えた並びの対の検収。同じ規則で件数だけが違う2つの世界を焼き、どちらも本番の描画経路へ通して、
//! シーンパスの発行数が件数に依らないことと、個体数が焼く工程の勘定と一致することを確かめ、目視用のPNGを書き出す。
//!
//! **これが部品の組み合わせでバリエーションを作るという設計の実証である。** 発行数が件数に比例し始めたら、
//! その設計は前提から誤っている。1つの規模だけでは、発行数がたまたまその件数と一致しているのか件数に依らないのかを
//! 見分けられないため、対にする。
//!
//! 家の並びと一間四方の骨格の並びが同じこの器を通るのは、焼く工程も走らせる工程も判定も完全に同じだからである。
//! 違うのは世界と出力ルートとシーン名と件数だけであり、それは`検収する並び1つ`と対の値が持つ。器を2つに分けると、
//! 同じ判定の写しが2つになり、片方だけ直した食い違いが起きる。
//!
//! 画素の合否判定を置かないのは、この入口の目的が「絵として成立しているか」の判断材料を出すことであり、
//! その判断は親エージェントの目視が行うためである。機械が見るのはvalidationが0件であることと、
//! 焼いた側の勘定と走らせた側の計数が噛み合うことだけである。
//! 参照: `_doc/設計/部品カタログと接合点.md`「検収の形」段4の完了条件

mod error;
mod judgment;
mod measurement;
mod run;
mod single_measurement;

use std::process::ExitCode;

use super::row_target::検収する並び1つ;
use crate::acceptance::検収シーン名;
/// 並び1つを焼いて走らせて測る工程と、その型付きエラーは、件数の対を持たない見本の撮影(`frame_chain`)も使う。
/// 器そのものを共有させないのは、あちらが対でないためである。突き合わせるべき数の関係が2つのあいだに無い。
/// **実測そのものは外へ出さない。** 呼び出し側は要約の1行だけを受け取り、内訳の読み方をこの束の外へ広げない。
pub(super) use error::部品で組んだ並びの検収エラー;
pub(super) use single_measurement::並び1つを焼いて走らせて測る;

/// 件数だけが違う2つの世界と、その対に共通の写し方。
pub(super) struct 件数を変えた並びの対 {
    入口の名前: &'static str,         // xtaskのコマンド名。成功と失敗の1行がこの名前で入口を名指す
    突き合わせの見出し: &'static str, // 対どうしの突き合わせの破れの文面が名乗る見出し
    シーン名: 検収シーン名,
    出力ディレクトリ: &'static str,
    少ないほう: 検収する並び1つ,
    多いほう: 検収する並び1つ,
}

impl 件数を変えた並びの対 {
    pub(super) const fn 生成する(
        入口の名前: &'static str,
        突き合わせの見出し: &'static str,
        シーン名: 検収シーン名,
        出力ディレクトリ: &'static str,
        少ないほう: 検収する並び1つ,
        多いほう: 検収する並び1つ,
    ) -> Self {
        Self {
            入口の名前,
            突き合わせの見出し,
            シーン名,
            出力ディレクトリ,
            少ないほう,
            多いほう,
        }
    }

    pub(super) fn 検収してコードへ変換する(&self) -> ExitCode {
        match self.検収する() {
            Ok(要約) => {
                println!("[xtask] {}成功: {要約}", self.入口の名前);
                ExitCode::SUCCESS
            }
            Err(理由) => {
                eprintln!("[xtask] {}失敗: {理由}", self.入口の名前);
                ExitCode::FAILURE
            }
        }
    }

    fn 検収する(&self) -> Result<String, 部品で組んだ並びの検収エラー> {
        if !crate::gen_source_assets::検証用ソースアセットを生成して成否を返す() {
            return Err(部品で組んだ並びの検収エラー::ソースアセットを生成できなかった);
        }
        let 少ないほうの実測 = self.並び1つを測る(&self.少ないほう)?;
        let 多いほうの実測 = self.並び1つを測る(&self.多いほう)?;
        judgment::対どうしを突き合わせる(self.突き合わせの見出し, &少ないほうの実測, &多いほうの実測)?;
        Ok(format!("{}。{}", 少ないほうの実測.要約の1行(), 多いほうの実測.要約の1行()))
    }

    fn 並び1つを測る(
        &self, 並び: &検収する並び1つ
    ) -> Result<measurement::並び1つの実測, 部品で組んだ並びの検収エラー> {
        並び1つを焼いて走らせて測る(並び, self.シーン名, self.出力ディレクトリ)
    }
}
