//! 骨格を連ねた見本5つを焼いて実機で描き、境目の姿と屋根の載り方を人が見るための絵を書き出す入口。
//! 上へ2段積んだ見本・横へ2ベイ継いだ見本・屋根を載せた1ベイの家・その家へ煙突を立てた家・屋根を載せた2段の家である。
//!
//! **この入口の目的は、正解表との突き合わせが通った組み立てそのものを絵にすることである。** 突き合わせが言えるのは
//! 姿勢が意図どおりであることまでであり、境目の胴差しの二重帯・柱の外面の連続部の深度の競合・継いだ面に壁が
//! 無いこと・軒の張り出しと破風の閉じ方・煙突が屋根の傾斜面を貫く姿は絵にしか出ない。合否は親の目視が確定する。
//!
//! 件数を変えた対の器(`scale_pair`)を通さないのは、この5つが対でないためである。あちらは同じ規則で件数だけを
//! 変えて発行数が件数に依らないことを実証し、こちらは違う規則の見本を並べて写すだけで、見本どうしに
//! 突き合わせるべき数の関係が無い。シーン名を1ベイ1段の並びと同じにしてあるため初期カメラも検収計画も、
//! 並び1つを焼いて走らせて測る工程も共有する。読む出力ルートだけが違う。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格の上下積層とベイの継ぎ口(2026-08-19 追加)」

use std::process::ExitCode;

use super::frame_bay_scene::{骨格方式のシーン名, 骨格方式の検収する並び};
use super::row_target::検収する並び1つ;
use super::scale_pair::{並び1つを焼いて走らせて測る, 部品で組んだ並びの検収エラー};
use crate::asset_generator::世界名;

/// 見本を建てる件数。敷地が1件ごとに天頂軸まわりの4分の1回転を選ぶため、4件あれば境目を違う方位から同時に写せる。
const 見本の件数: u64 = 4;

const 出力ディレクトリ: &str = "target/part_frame_chain_draw";

const 二段に積んだ骨格: 検収する並び1つ = 骨格方式の検収する並び!(
    "2段に積んだ骨格の見本",
    世界名::二段に積んだ骨格の見本の世界,
    "target/part_frame_two_story_assets",
    "two_story",
    見本の件数
);

const 横に二ベイ継いだ骨格: 検収する並び1つ = 骨格方式の検収する並び!(
    "横に2ベイ継いだ骨格の見本",
    世界名::横に二ベイ継いだ骨格の見本の世界,
    "target/part_frame_row_two_assets",
    "row_two",
    見本の件数
);

const 屋根を載せた一間四方の家: 検収する並び1つ = 骨格方式の検収する並び!(
    "屋根を載せた1ベイの家の見本",
    世界名::屋根を載せた一間四方の家の見本の世界,
    "target/part_frame_bay_house_assets",
    "bay_house",
    見本の件数
);

const 屋根を載せた二段の家: 検収する並び1つ = 骨格方式の検収する並び!(
    "屋根を載せた2段の家の見本",
    世界名::屋根を載せた二段の家の見本の世界,
    "target/part_frame_two_story_house_assets",
    "two_story_house",
    見本の件数
);

const 煙突を付けた一間四方の家: 検収する並び1つ = 骨格方式の検収する並び!(
    "煙突を付けた1ベイの家の見本",
    世界名::煙突を付けた一間四方の家の見本の世界,
    "target/part_frame_bay_house_chimney_assets",
    "bay_house_chimney",
    見本の件数
);

/// 焼いて走らせる順。上から順に測り、1つでも破れたらそこで止まる。
const 見本一覧: [検収する並び1つ; 5] = [
    二段に積んだ骨格,
    横に二ベイ継いだ骨格,
    屋根を載せた一間四方の家,
    煙突を付けた一間四方の家,
    屋根を載せた二段の家,
];

pub(super) fn 実行する() -> ExitCode {
    match 撮影する() {
        Ok(要約) => {
            println!("[xtask] part-frame-chain-draw成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] part-frame-chain-draw失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

fn 撮影する() -> Result<String, 部品で組んだ並びの検収エラー> {
    if !crate::gen_source_assets::生成する() {
        return Err(部品で組んだ並びの検収エラー::ソースアセットを生成できなかった);
    }
    let mut 要約一覧: Vec<String> = Vec::with_capacity(見本一覧.len());
    for 見本 in &見本一覧 {
        要約一覧.push(並び1つを焼いて走らせて測る(見本, 骨格方式のシーン名, 出力ディレクトリ)?.要約の1行());
    }
    Ok(要約一覧.join("。"))
}
