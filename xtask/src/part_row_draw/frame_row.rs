//! 部品で組んだ一間四方の骨格の並びの検収入口。10棟と100棟の対を`scale_pair`の器へ渡すだけであり、
//! この階層が持つのは世界と出力ルートと件数の対応だけである。シーンの綴りと焼き先の組み方は`frame_bay_scene`が持つ。
//!
//! **家の並びと世界を分けるのは、組み立ての形が違うものを別々の計器で見るためである。** 家は一体の階を積み、
//! 骨格は枠へ壁をはめる。同じ世界へ混ぜると、発行数が件数に依らないことが破れたときに、どちらの組み立てが
//! 壊したのかを絵と数から切り分けられない。
//!
//! シーン名がベイ1つを近くで写す初期カメラと、書き換えもピクセル判定も持たない検収計画を選ばせる。
//! 10棟と100棟は同じシーン名を持ち、読む出力ルートだけが違う。
//! 参照: `_doc/設計/部品カタログと接合点.md`「骨格と壁の対、扉の対」

use std::process::ExitCode;

use super::frame_bay_scene::{骨格方式のシーン名, 骨格方式の検収する並び};
use super::row_target::検収する並び1つ;
use super::scale_pair::件数を変えた並びの対;
use crate::asset_generator::世界名;
use crate::verify::検証の出力の置き場名;

const 絵の書き出し先: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("part_frame_row_draw");

const 十棟: 検収する並び1つ = 骨格方式の検収する並び!(
    "10棟の一間四方の骨格の並び",
    世界名::一間四方の骨格を十棟建てた世界,
    "part_frame_row_ten_assets",
    "ten",
    10
);

const 百棟: 検収する並び1つ = 骨格方式の検収する並び!(
    "100棟の一間四方の骨格の並び",
    世界名::一間四方の骨格を百棟建てた世界,
    "part_frame_row_hundred_assets",
    "hundred",
    100
);

const 一間四方の骨格の並びの対: 件数を変えた並びの対 = 件数を変えた並びの対::生成する(
    "part-frame-row-draw",
    "10棟と100棟の突き合わせ",
    骨格方式のシーン名,
    絵の書き出し先,
    十棟,
    百棟,
);

pub(super) fn 一間四方の骨格の並びの対を検収する() -> ExitCode {
    一間四方の骨格の並びの対.検収してコードへ変換する()
}
