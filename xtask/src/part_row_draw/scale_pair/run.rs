//! 並び1つぶんの起動の指定。受け取るのは並びとシーン名、返すのは実行環境へ渡す起動指定である。
//! 起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! シーン名が初期カメラと検収計画の両方を選ぶ。件数の少ないほうと多いほうは同じシーン名を持ち、読む出力ルートだけが違う。
//! 空は`--sky`で明示する。世界の方針が空ありになるのは名前が`terrain`で始まる世界だけであり、
//! 部品で組んだ並びの世界はそこへ入らないためである。
//!
//! 一日内時刻を15時にするのは、太陽が斜めから当たり、面ごとの向きの違いが明暗で見分けられるためである。
//! 真上からの光では垂直な面がどれも同じ明るさになり、向きの違いが絵に出ない。

use std::path::PathBuf;

use super::super::row_target::検収する並び1つ;
use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 描画フレーム数, 描画検収の実行環境, 検収エラー, 検収シーン名
};

const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(180);

/// 一日内時刻15時。
const 一日内秒: &str = "54000";

const 報告を出させる選択肢: [&str; 3] = ["--sky", "--report-draw-issue", "--report-memory"];

pub(super) fn 実行環境を作る(
    並び: &検収する並び1つ, 出力ディレクトリ: PathBuf
) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        並び.実行時アセットルート(),
        出力ディレクトリ,
    )
}

pub(super) fn 起動指定を組み立てる(シーン名: 検収シーン名) -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数)
        .値を持つ選択肢を足す("--time-of-day", 一日内秒)
        .選択肢をまとめて足す(&報告を出させる選択肢)
}
