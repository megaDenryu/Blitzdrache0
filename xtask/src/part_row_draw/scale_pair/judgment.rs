//! 件数を変えた並びの対の判定。受け取るのは並びごとの実測、返すのは合否である。
//!
//! 判定は2段ある。1段目は並び1つの中で、焼いた側が数えた勘定と走らせた側が出した計数が噛み合うことを見る。
//! 2段目は件数の少ないほうと多いほうのあいだで、発行数と部品の種類数が同じであることと、個体数だけが増えることを見る。
//!
//! **2段目が実証の主張そのものである。** 1つの規模だけでは、発行数がたまたまその件数と一致しているのか
//! 件数に依らないのかを見分けられない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「検収の形」段4の完了条件

use super::measurement::並び1つの実測;
use crate::acceptance::{判定の名前, 判定の破れ};

/// **発行数の期待値に最詳細段のプリミティブ数を使う前提は、全個体が最詳細段で描かれることである。**
/// 家の部品も骨格と壁の部品も段を1つしか持たないため、どの距離から写しても描かれるのは最詳細段である。
///
/// この世界が持つ群でない描画対象の数。地面1つだけである。描画発行はプリミティブごとに1回であり、
/// 地面は1つの材質しか持たないため、地面が立てる発行も1回である。
const 地面の描画対象の数: u64 = 1;

pub(super) fn 並び1つを検査する(実測: &並び1つの実測) -> Result<(), 判定の破れ> {
    let 呼び名 = 実測.並び.呼び名();
    crate::count_consistency::計数の整合を検査する(呼び名, &実測.計数)?;
    判定名(呼び名, "検証層の指摘").零件であることを課す(実測.計数.validation件数)?;
    判定名(呼び名, "組み上げた件数(宣言した件数がそのまま焼かれるはずである)").一致を課す(実測.勘定.件数, 実測.並び.宣言した件数())?;
    判定名(呼び名, "材質スロット数の総和(最詳細段のプリミティブの数と一致するはずである)")
        .一致を課す(実測.勘定.材質スロット数の総和, 実測.勘定.最詳細段のプリミティブ数の総和)?;
    判定名(呼び名, "群でない描画対象の数(地面1つだけのはずである)").一致を課す(実測.群でない描画対象の数(), 地面の描画対象の数)?;
    判定名(
        呼び名,
        "シーンパスの発行数(地面の1と部品ごとの最詳細段のプリミティブ数の総和の和になるはずである)",
    )
    .一致を課す(実測.シーンパスの発行数(), 地面の描画対象の数 + 実測.勘定.最詳細段のプリミティブ数の総和)?;
    判定名(
        呼び名,
        "可視判定へ登録された個体の候補数(焼く工程が据えた部品の個体数と一致するはずである)",
    )
    .一致を課す(実測.群の個体の候補数(), 実測.勘定.据えた部品の個体数)
}

/// 件数の少ないほうと多いほうの突き合わせ。発行数と部品の種類数が件数に依らず、個体数だけが増えることを見る。
pub(super) fn 対どうしを突き合わせる(
    見出し: &'static str,
    少ないほう: &並び1つの実測,
    多いほう: &並び1つの実測,
) -> Result<(), 判定の破れ> {
    判定名(見出し, "部品の種類数(件数を変えても同じはずである)").一致を課す(少ないほう.勘定.部品の種類数, 多いほう.勘定.部品の種類数)?;
    判定名(見出し, "材質スロット数の総和(件数を変えても同じはずである)")
        .一致を課す(少ないほう.勘定.材質スロット数の総和, 多いほう.勘定.材質スロット数の総和)?;
    判定名(見出し, "シーンパスの発行数(件数を10倍にしても同じはずである)")
        .一致を課す(少ないほう.シーンパスの発行数(), 多いほう.シーンパスの発行数())?;
    判定名(
        見出し,
        "件数の多いほうの個体数(少ないほうより多いはずである。増えるのは配置列の長さだけである)",
    )
    .下限を課す(多いほう.群の個体の候補数(), 少ないほう.群の個体の候補数() + 1)
}

fn 判定名(呼び名: &str, 見るもの: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{呼び名}の{見るもの}"))
}
