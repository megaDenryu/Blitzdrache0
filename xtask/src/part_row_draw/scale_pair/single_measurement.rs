//! 並び1つを焼いて走らせて測る工程。受け取るのは検収する並びとシーン名と絵の書き出し先、返すのは並び1つの実測である。
//!
//! 対の側から分けるのは、これが名前の付く独立した工程だからである。焼き上がりを消す・焼く・勘定の行を読む・
//! 実行時形式の実在を確かめる・実機で描く・計数を読む・絵を書き出す・並び1つの判定を通す、までを一続きに行い、
//! 呼び出し側は中身を知らずに「並び1つを測れ」と言えばよい。対の側が持つのは2つの実測を突き合わせることだけである。
//!
//! 並び1つの判定をここで通すのは、破れたときにどちらの規模で落ちたかを、対どうしの突き合わせより先に言うためである。

use super::super::row_target::検収する並び1つ;
use super::super::tally_line::焼いた並びの勘定;
use super::error::部品で組んだ並びの検収エラー;
use super::measurement::並び1つの実測;
use super::{judgment, run};
use crate::acceptance::検収シーン名;
use crate::verify::{検証の出力の置き場名, 検証の出力ルート};

pub(in crate::part_row_draw) fn 並び1つを焼いて走らせて測る(
    並び: &検収する並び1つ,
    シーン名: 検収シーン名,
    出力ディレクトリ: 検証の出力の置き場名,
) -> Result<並び1つの実測, 部品で組んだ並びの検収エラー> {
    並び
        .前回の焼き上がりを消す()
        .map_err(部品で組んだ並びの検収エラー::前回の焼き上がりを消せなかった)?;
    let 標準出力 = crate::compile_assets::既定のソースから焼き標準出力を返す(&並び.出力ルート(), 並び.世界())?;
    print!("{標準出力}");
    let 勘定 = 焼いた並びの勘定::標準出力から読む(標準出力)?;
    並び
        .焼き上がりの確かめ方()
        .焼き上がりを確かめる(true)
        .map_err(部品で組んだ並びの検収エラー::検収世界を用意できなかった)?;
    let 実行環境 = run::実行環境を作る(並び, 検証の出力ルート::既定().名前が指す置き場(出力ディレクトリ))?;
    let 実行 = 実行環境.描いて読み戻す(並び.実行名(), &run::起動指定を組み立てる(シーン名))?;
    let 計数 = crate::report_parse::取り出す(実行.報告())?;
    let 絵 = 実行.書き出し先().目視用の絵へ変換する()?;
    let 実測 = 並び1つの実測 {
        並び: 並び.clone(),
        勘定,
        計数,
        絵,
    };
    judgment::並び1つを検査する(&実測)?;
    Ok(実測)
}
