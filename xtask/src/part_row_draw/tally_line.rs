//! アセットコンパイラの標準出力から、部品で組んだ並びの勘定の1行を取り出す型。受け取るのは取り込んだ標準出力、
//! 返すのは件数と部品の種類数と材質スロット数の総和とプリミティブ数の総和と据えた部品の個体数である。
//!
//! 5つを1つの型が持つのは、どれも同じ1行からしか読めず、読み落としを同じ場所で拒みたいためである。
//! 期待値を検収の側に定数で持たないのは、部品を1つ足したときに検収だけが無言で通らなくなるためである。
//!
//! 注意: 行の綴りは書き手(`crates/blitz_asset_compiler/src/part_row/tally.rs`)にも同じものがある。
//! 両側にあることは`cargo xtask conform`の綴りの契約の検査が守る。

use crate::acceptance::{判定の名前, 検収の実行名, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

/// 部品で組んだ並びの勘定の行を見分ける語。コンパイラは同じ見出しで始まる行を何本も出すため、この語で1本へ絞る。
///
/// 注意: 見分ける語に欄の鍵を含めない。含めると1つの綴りが「行の見分け」と「鍵」の2つの役割を持ち、
/// 鍵だけを台帳へ登録し忘れても、見分ける語の側が契約を満たすため検査が通ってしまう。
const 並びの行を見分ける語: &str = "部品で組んだ並び:";

const 件数の欄: &str = "組み上げた件数=";
const 部品の種類数の欄: &str = "部品の種類数=";
const 材質スロット数の欄: &str = "材質スロット数の総和=";
const プリミティブ数の欄: &str = "プリミティブ数の総和=";
const 個体数の欄: &str = "据えた部品の個体数=";

/// 焼く工程が数えた部品で組んだ並びの勘定。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 焼いた並びの勘定 {
    pub(crate) 件数: u64,
    pub(crate) 部品の種類数: u64,
    pub(crate) 材質スロット数の総和: u64,
    pub(crate) プリミティブ数の総和: u64,
    pub(crate) 据えた部品の個体数: u64,
}

impl 焼いた並びの勘定 {
    pub(crate) fn 標準出力から読む(標準出力: String) -> Result<Self, 検収エラー> {
        let 報告 = 終了時報告::取り込む(&検収の実行名::定数から生成する("part_row_compile"), 標準出力, String::new());
        Ok(Self {
            件数: 欄を読む(&報告, 件数の欄)?,
            部品の種類数: 欄を読む(&報告, 部品の種類数の欄)?,
            材質スロット数の総和: 欄を読む(&報告, 材質スロット数の欄)?,
            プリミティブ数の総和: 欄を読む(&報告, プリミティブ数の欄)?,
            据えた部品の個体数: 欄を読む(&報告, 個体数の欄)?,
        })
    }
}

fn 欄を読む(報告: &終了時報告, 欄の綴り: &str) -> Result<u64, 検収エラー> {
    let 行一覧 = 報告.見出しで始まる行の一覧(&報告の見出し::定数から生成する("[compile_assets] "));
    let 判定名 = 判定の名前::組み立てた綴りから生成する(format!("アセットコンパイラの報告の並びの行の{欄の綴り}"));
    let 行 = 行一覧
        .iter()
        .find(|行| 行.原文().contains(並びの行を見分ける語))
        .ok_or_else(|| 判定名.あるはずのものが無い破れ())?;
    行.鍵に結ばれた数(
        &報告の行の鍵::組み立てた綴りから生成する(欄の綴り.to_string()),
        鍵に値が結ばれる形::この綴りに続く数字の並びが値である,
    )
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::{
        プリミティブ数の欄, 並びの行を見分ける語, 件数の欄, 個体数の欄, 材質スロット数の欄, 焼いた並びの勘定, 部品の種類数の欄
    };

    /// 焼く工程が出す形の1行を、この読み取りが持つ綴りだけから組み立てる。綴りを試験へ直に書かないのは、
    /// 写しが3つ目になるためである。出す側との綴りの一致は`cargo xtask conform`の綴りの契約が守る。
    fn 勘定の行を組み立てる() -> String {
        format!(
            "[compile_assets] {並びの行を見分ける語} {件数の欄}4 {部品の種類数の欄}3 {材質スロット数の欄}4 {プリミティブ数の欄}4 {個体数の欄}20\n"
        )
    }

    #[test]
    fn 勘定の行から5つの欄を読む() {
        let 勘定 = 焼いた並びの勘定::標準出力から読む(勘定の行を組み立てる()).unwrap();
        assert_eq!(勘定.件数, 4);
        assert_eq!(勘定.部品の種類数, 3);
        assert_eq!(勘定.材質スロット数の総和, 4);
        assert_eq!(勘定.プリミティブ数の総和, 4);
        assert_eq!(勘定.据えた部品の個体数, 20);
    }

    #[test]
    fn 勘定の行が無ければ破れとして返す() {
        let 別の行 = "[compile_assets] 焼き直したチャンク数=1 据え置いたチャンク数=0\n".to_string();
        assert!(焼いた並びの勘定::標準出力から読む(別の行).is_err());
    }
}
