//! 部品で組んだ並びのパスの綴りが満たすべき決め事と、それを構築時に調べる述語。
//!
//! **決め事の正本をここ1つに置く。** 置き場の型と焼き上がりのファイルの型が同じ2つの決め事を表裏で使う。
//! 両方の型がそれぞれ綴りを持つと、片方だけを直した食い違いが起きる。
//!
//! 実行時形式の拡張子だけは、この階層より上に正本がある。焼く側(`blitz_asset_compiler`)がその綴りで書き出すため、
//! 写しをここへ書くと、焼く側が拡張子を変えたときに検収の側だけが古い綴りを見て、
//! 焼けていない世界を焼けたと誤診断する。
//!
//! `const fn`で書くのは、置き場も焼き上がりのファイルもどちらも定数として書かれるためである。
//! 定数として使う限り、破れは実行ではなくコンパイルで落ちる。標準ライブラリの`starts_with`と`ends_with`は
//! `const fn`でないため、バイト列を突き合わせる形で書く。綴りはどれも原文のリテラルであり、長さは高々数十バイトである。

use blitz_asset_compiler::実行時形式のアセットの拡張子 as 実行時形式の拡張子;

/// 消してよい置き場の親。この綴りで始まらないディレクトリを、この入口は消さない。
/// 焼き上がりのファイルも同じ木の下にしか置かれない。
const 消してよい木の根: &str = "target/";

/// この綴りが、消してよいビルドの出力の木の下を指しているか。
pub(super) const fn 消してよい木の下を指すか(綴り: &str) -> bool {
    綴りの先頭が一致するか(綴り, 消してよい木の根)
}

/// この綴りが、実行時形式のファイル1件を指しているか。ディレクトリを指す綴りは偽になる。
pub(super) const fn 実行時形式のファイルを指すか(綴り: &str) -> bool {
    綴りの末尾が一致するか(綴り, 実行時形式の拡張子)
}

const fn 綴りの先頭が一致するか(綴り: &str, 先頭: &str) -> bool {
    let (本体, 期待) = (綴り.as_bytes(), 先頭.as_bytes());
    if 本体.len() < 期待.len() {
        return false;
    }
    同じ並びか(本体, 期待, 0)
}

const fn 綴りの末尾が一致するか(綴り: &str, 末尾: &str) -> bool {
    let (本体, 期待) = (綴り.as_bytes(), 末尾.as_bytes());
    if 本体.len() < 期待.len() {
        return false;
    }
    同じ並びか(本体, 期待, 本体.len() - 期待.len())
}

/// 本体の指定の位置から、期待する並びと同じバイトが続くか。
const fn 同じ並びか(本体: &[u8], 期待: &[u8], 開始: usize) -> bool {
    let mut 添字 = 0;
    while 添字 < 期待.len() {
        if 本体[開始 + 添字] != 期待[添字] {
            return false;
        }
        添字 += 1;
    }
    true
}
