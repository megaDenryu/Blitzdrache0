//! 焼き上がりを確かめるファイル: 焼く工程が実行時形式を実際に作ったことを、実在で確かめる相手のファイルを表す型。
//!
//! 実在の確認が要るのは、外部のアセットリポジトリが無い環境では部品の宣言が飛ばされ、実行時形式が作られないまま
//! 焼く工程が成功するためである。**確かめ方が誤ったパスを見ると、焼けていない世界を焼けたと誤診断する。**
//!
//! 置き場と同じ裸の`&str`で持つと、隣り合う引数で受けるため取り違えても型が通る。実行時形式のファイルを指すことを
//! 課し、置き場の側はそれを拒むため、2つを入れ替えた宣言はどちらの側でもコンパイルで落ちる。
//! 決め事の正本は`row_path_rule`が持つ。
//!
//! 注意: 破れは書き誤りであるため、定数として使う限りコンパイル時に落ちる。

use super::row_path_rule::{実行時形式のファイルを指すか, 消してよい木の下を指すか};

#[derive(Debug, Clone, Copy)]
#[repr(transparent)]
pub(super) struct 焼き上がりを確かめるファイル(&'static str);

impl 焼き上がりを確かめるファイル {
    pub(super) const fn 定数から生成する(綴り: &'static str) -> Self {
        if !消してよい木の下を指すか(綴り) {
            panic!("焼き上がりを確かめるファイルが消してよい木の下にない(焼き上がりはビルドの出力の木の中にしか置かれない)");
        }
        if !実行時形式のファイルを指すか(綴り) {
            panic!("焼き上がりを確かめるファイルが実行時形式のファイルを指していない(並びの実行時形式の置き場と取り違えている)");
        }
        Self(綴り)
    }

    /// 実在を確かめる相手を組み立てるための綴り。生のパスへ戻るのはここだけである。
    pub(super) fn 綴り(self) -> &'static str {
        self.0
    }
}
