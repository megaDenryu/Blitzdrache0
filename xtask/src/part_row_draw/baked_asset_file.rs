//! 焼き上がりを確かめるファイル: 焼く工程が実行時形式を実際に作ったことを、実在で確かめる相手のファイルを表す型。
//!
//! 実在の確認が要るのは、外部のアセットリポジトリが無い環境では部品の宣言が飛ばされ、実行時形式が作られないまま
//! 焼く工程が成功するためである。**確かめ方が誤ったパスを見ると、焼けていない世界を焼けたと誤診断する。**
//!
//! 置き場の名前と焼き上がりのファイル名を別々に持つのは、どちらも綴りであり、1つへ潰すと取り違えても型が通るためである。
//! ファイル名が実行時形式を指すことを課し、置き場の側はそれを拒むため、2つを入れ替えた宣言はどちらの側でも
//! コンパイルで落ちる。決め事の正本は`row_path_rule`が持つ。
//!
//! 注意: 破れは書き誤りであるため、定数として使う限りコンパイル時に落ちる。

use super::row_path_rule::実行時形式のファイルを指すか;
use crate::verify::検証の出力の置き場名;

#[derive(Debug, Clone, Copy)]
pub(super) struct 焼き上がりを確かめるファイル {
    置き場: 検証の出力の置き場名,
    ファイル名: &'static str,
}

impl 焼き上がりを確かめるファイル {
    pub(super) const fn 定数から生成する(置き場: 検証の出力の置き場名, ファイル名: &'static str) -> Self {
        if !実行時形式のファイルを指すか(ファイル名) {
            panic!("焼き上がりを確かめるファイルが実行時形式のファイルを指していない(並びの実行時形式の置き場と取り違えている)");
        }
        Self { 置き場, ファイル名 }
    }

    pub(super) fn 置き場(self) -> 検証の出力の置き場名 {
        self.置き場
    }

    pub(super) fn ファイル名(self) -> &'static str {
        self.ファイル名
    }
}
