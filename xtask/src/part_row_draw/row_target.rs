//! 検収する並び1つ: 件数だけが違う2つの世界のうちの1つを指す値。焼く先・走らせる先・実行名・宣言した件数を、
//! この1つの値が同時に答える。
//!
//! 5つを1つの値から引くのは、規模ごとに別々の綴りを呼び出し側が組むと、10件の世界を焼いて100件の実行時形式を
//! 読む組み合わせが型を通るためである。並びを選べば行き先がすべて決まる。
//!
//! 前回の焼き上がりを消す口をこの型が持つのは、消してよい置き場を知っているのがこの型だけだからである。

use std::path::Path;

use crate::acceptance::{実行時アセットルート, 検収の実行名};
use crate::asset_generator::世界名;
use crate::world_setup::検収世界の用意;

#[derive(Debug, Clone)]
pub(super) struct 検収する並び1つ {
    呼び名: &'static str,
    世界: 世界名,
    /// 焼く先であり、そのまま走らせる側が読む実行時アセットルートでもある。2つの名前で持つと、
    /// 焼いた先と読む先が食い違う値の組を書けてしまう。
    出力ルート: &'static str,
    焼き上がりのファイル: &'static str,
    実行名: 検収の実行名,
    宣言した件数: u64,
}

impl 検収する並び1つ {
    pub(super) const fn 生成する(
        呼び名: &'static str,
        世界: 世界名,
        出力ルート: &'static str,
        焼き上がりのファイル: &'static str,
        実行名: 検収の実行名,
        宣言した件数: u64,
    ) -> Self {
        Self {
            呼び名,
            世界,
            出力ルート,
            焼き上がりのファイル,
            実行名,
            宣言した件数,
        }
    }

    pub(super) fn 呼び名(&self) -> &'static str {
        self.呼び名
    }

    pub(super) fn 世界(&self) -> 世界名 {
        self.世界
    }

    pub(super) fn 出力ルート(&self) -> &'static Path {
        Path::new(self.出力ルート)
    }

    pub(super) fn 実行時アセットルート(&self) -> 実行時アセットルート {
        実行時アセットルート::綴りから生成する(self.出力ルート)
    }

    /// 絵のファイル名になり、失敗の文面もこの名前で実行を名指す。
    pub(super) fn 実行名(&self) -> 検収の実行名 {
        self.実行名.clone()
    }

    /// 宣言が何件を建てると書いたか。焼く工程が数えた件数がこの値と一致することを判定が課す。
    pub(super) fn 宣言した件数(&self) -> u64 {
        self.宣言した件数
    }

    /// 焼き上がりを名指しで確かめる相手。外部のアセットリポジトリが無い環境では部品の宣言が飛ばされ、
    /// 実行時形式が作られないまま焼く工程が成功する。
    pub(super) fn 焼き上がりの確かめ方(&self) -> 検収世界の用意 {
        検収世界の用意::生成する(self.呼び名, self.焼き上がりのファイル)
    }

    /// 焼く前に前回の焼き上がりを消す。**この入口は焼く工程の報告の行を期待値に使うため、生成台帳が据え置きを選ぶと
    /// 行が1本も出ず、比べる相手を失う。** 消してよいのは、この置き場をこの入口だけが使うためである。
    /// まだ無いことは破れではない。
    pub(super) fn 前回の焼き上がりを消す(&self) -> std::io::Result<()> {
        match std::fs::remove_dir_all(self.出力ルート()) {
            Err(誤り) if 誤り.kind() == std::io::ErrorKind::NotFound => Ok(()),
            他 => 他,
        }
    }
}
