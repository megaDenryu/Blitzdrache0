//! 並びの実行時形式の置き場: 部品で組んだ並び1つを焼く先のディレクトリを表す型。走らせる側が読む実行時アセットルートでもある。
//!
//! 焼き上がりを確かめるファイルと同じ裸の`&str`で持つと、隣り合う引数で受けるため取り違えても型が通る。
//! **取り違えた宣言が通ると、前回の焼き上がりを消す操作が誤ったディレクトリを消す。**
//! この型は実行時形式のファイルを指す綴りを拒み、ファイルの側はそれを指すことを課すため、
//! 2つを入れ替えた宣言はどちらの側でもコンパイルで落ちる。決め事の正本は`row_path_rule`が持つ。
//!
//! 消してよい木の下であることは、`検証の出力の置き場名`を持つこと自体が保証する。この型の値は`remove_dir_all`の
//! 相手になるため、木の外を指せないことが要る。
//!
//! 注意: 破れは書き誤りであるため、定数として使う限りコンパイル時に落ちる。

use std::path::PathBuf;

use super::row_path_rule::実行時形式のファイルを指すか;
use crate::verify::{検証の出力の置き場名, 検証の出力ルート};

#[derive(Debug, Clone, Copy)]
#[repr(transparent)]
pub(super) struct 並びの実行時形式の置き場(検証の出力の置き場名);

impl 並びの実行時形式の置き場 {
    pub(super) const fn 定数から生成する(名前: 検証の出力の置き場名) -> Self {
        if 実行時形式のファイルを指すか(名前.綴りを見せる()) {
            panic!("並びの実行時形式の置き場が実行時形式のファイルを指している(焼き上がりを確かめるファイルと取り違えている)");
        }
        Self(名前)
    }

    /// 焼く先のディレクトリ。名前がパスへ組み上がる口はここだけである。
    pub(super) fn パス(self) -> PathBuf {
        検証の出力ルート::既定().名前が指す置き場(self.0)
    }
}
