//! 並びの実行時形式の置き場: 部品で組んだ並び1つを焼く先のディレクトリを表す型。走らせる側が読む実行時アセットルートでもある。
//!
//! 焼き上がりを確かめるファイルと同じ裸の`&str`で持つと、隣り合う引数で受けるため取り違えても型が通る。
//! **取り違えた宣言が通ると、前回の焼き上がりを消す操作が誤ったディレクトリを消す。**
//! この型は実行時形式のファイルを指す綴りを拒み、ファイルの側はそれを指すことを課すため、
//! 2つを入れ替えた宣言はどちらの側でもコンパイルで落ちる。決め事の正本は`row_path_rule`が持つ。
//!
//! 消してよい木の下であることを課すのは、この型の値が`remove_dir_all`の相手になるためである。
//! 消してよいのはビルドの出力の木の中だけであり、それ以外を指す綴りは書き誤りである。
//!
//! 注意: 破れは書き誤りであるため、定数として使う限りコンパイル時に落ちる。

use std::path::Path;

use super::row_path_rule::{実行時形式のファイルを指すか, 消してよい木の下を指すか};

#[derive(Debug, Clone, Copy)]
#[repr(transparent)]
pub(super) struct 並びの実行時形式の置き場(&'static str);

impl 並びの実行時形式の置き場 {
    pub(super) const fn 定数から生成する(綴り: &'static str) -> Self {
        if !消してよい木の下を指すか(綴り) {
            panic!("並びの実行時形式の置き場が消してよい木の下にない(この入口は焼く前にこの置き場を消すため、ビルドの出力の木の外を指せない)");
        }
        if 実行時形式のファイルを指すか(綴り) {
            panic!("並びの実行時形式の置き場が実行時形式のファイルを指している(焼き上がりを確かめるファイルと取り違えている)");
        }
        Self(綴り)
    }

    /// 焼く先のディレクトリ。生のパスへ戻るのはここと`綴り`だけである。
    pub(super) fn パス(self) -> &'static Path {
        Path::new(self.0)
    }

    /// 走らせる側が読む実行時アセットルートを組むための綴り。
    pub(super) fn 綴り(self) -> &'static str {
        self.0
    }
}
