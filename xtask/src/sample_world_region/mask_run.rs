//! 領域マスクを撮る起動の指定。返すのは実行環境へ渡す起動指定である。
//!
//! 起動指定を領域の識別と同じモジュールに置くのは、識別が「ライティングもポスト処理も空も外した1枚」を
//! 前提にしているためである。入口ごとに指定を書くと、片方だけが条件を変えたときに識別が黙って別の絵を読む。
//!
//! `--unlit`がどの面にもベースカラー係数をそのまま書かせ、`--no-post`が明るさの圧縮を外し、
//! `--no-sky`が背景の空を外す。この3つが揃って初めて、材質の宣言の色と読み戻した色が対応する。
//! 時間再構成は`--no-taa`で外す。この入口の判定がバイト一致に依るため、フレームをまたぐ混合が入ると前のフレームの残りが絵に混ざる。

use crate::acceptance::{アプリの起動指定, 描画フレーム数, 検収の実行名};
use crate::visual_sample_world::目視見本世界のシーン名;

/// 描くフレーム数。時刻の絵と同じ本数であり、小物の詳細段の選択が定常へ入る状態まで進める。
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(120);
const 領域を分けるための選択肢: [&str; 4] = ["--no-sky", "--no-post", "--unlit", "--no-taa"];

/// 領域マスクの書き出しの基準名。この1枚を撮る入口はどれもこの名前を使う。
pub const 領域マスクの実行名: 検収の実行名 = 検収の実行名::定数から生成する("ground_mask");

pub fn 領域マスクの起動指定を組み立てる() -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(目視見本世界のシーン名, フレーム数).選択肢をまとめて足す(&領域を分けるための選択肢)
}
