//! 線形のベースカラー係数を、読み戻し画像の8ビット値へ写す工程。受け取るのは線形の3成分と1枚の画像、
//! 返すのはその画像の中に実在する最も近い色である。
//!
//! 期待値を計算した色そのものと突き合わせないのは、伝達関数の丸めが境目の値で1段ずれうるためである。
//! 画像に実在する色の中から最も近いものを選び、成分ごとの差が許容の内側にあることだけを要求する。
//! 許容を超えた色しか無ければ、その材質が絵に出ていないか宣言が正本とずれていることを意味するため落とす。

use crate::vegetation_run::実行結果;

/// 実在する色として認める成分ごとの差。伝達関数の丸めが動く幅である1段ぶんに、
/// 読み戻しの経路が持ちうる同じ幅を足して2段までを認める。
const 許容する成分差: i32 = 2;

pub(super) fn 画像の中の該当色を探す(
    画像: &実行結果, 線形のベースカラー: [f32; 3], 呼び名: &str
) -> Result<[u8; 3], String> {
    let 期待 = 線形のベースカラー.map(符号値へ写す);
    let 候補 = 画像
        .rgba8
        .chunks_exact(4)
        .map(|画素| [画素[0], 画素[1], 画素[2]])
        .min_by_key(|色| 成分差の最大(*色, 期待))
        .ok_or_else(|| format!("{呼び名}を探す画像に画素が1つも無い"))?;
    if 成分差の最大(候補, 期待) > 許容する成分差 {
        return Err(format!("{呼び名}のベースカラー{期待:?}に近い色が絵に無い(最も近いのは{候補:?})"));
    }
    Ok(候補)
}

fn 成分差の最大(色: [u8; 3], 期待: [u8; 3]) -> i32 {
    (0..3)
        .map(|添字| (i32::from(色[添字]) - i32::from(期待[添字])).abs())
        .max()
        .unwrap_or(i32::MAX)
}

/// 標準的な伝達関数で線形の0から1を8ビットの符号値へ写す。
fn 符号値へ写す(線形: f32) -> u8 {
    let 符号化 = if 線形 <= 0.003_130_8 {
        12.92 * 線形
    } else {
        1.055 * 線形.powf(1.0 / 2.4) - 0.055
    };
    最近接の段(符号化.clamp(0.0, 1.0) * 255.0)
}

/// 実数に最も近い0から255の段。浮動小数から整数への安全な標準変換が無く`as`キャストは規約で禁止のため、
/// 段を1つずつ進める比較で求める。呼ぶのは材質の数だけであり、画素ごとには呼ばない。
fn 最近接の段(値: f32) -> u8 {
    let mut 段 = 0_u8;
    while 段 < u8::MAX && f32::from(段) + 0.5 < 値 {
        段 += 1;
    }
    段
}
