//! 材質見本の球ごとの画素を分ける工程。受け取るのは領域マスクの1枚と球の材質、
//! 返すのは左から右へ並べた球ごとの画素添字の列である。
//!
//! 同じ材質の球はベースカラーを共有するため、色の一致だけでは1つの球を切り出せない。球どうしは間隔が直径より
//! 広く、背景の台座は別の色であるため、色が一致する画素を4近傍で繋いだかたまりが球1つに対応する。
//! かたまりの数が宣言の球の数と違えば、球が隠れたか色が変わったことを意味するため落とす。
//!
//! かたまりを画素の横位置の平均で並べるのは、正本が球の中心のx座標を番号の昇順で置いており、
//! 左から右への並びが宣言の並びと一致するためである。

use super::sample_bodies::球の材質;
use crate::vegetation_run::実行結果;

pub(super) fn 球ごとの画素を分ける(
    画像: &実行結果, 色: [u8; 3], 材質: 球の材質, 期待する球の数: usize
) -> Result<Vec<Vec<usize>>, String> {
    let 該当か = 該当画素の表を作る(画像, 色);
    let mut かたまり一覧 = 繋がりで分ける(&該当か, 画像.幅, 画像.高さ);
    if かたまり一覧.len() != 期待する球の数 {
        return Err(format!(
            "{}の球が{}個に分かれた(宣言は{期待する球の数}個)。球が隠れたか材質の宣言が動いている",
            材質.呼び名(),
            かたまり一覧.len()
        ));
    }
    かたまり一覧.sort_by(|左, 右| 横位置の平均(左, 画像.幅).total_cmp(&横位置の平均(右, 画像.幅)));
    Ok(かたまり一覧)
}

fn 該当画素の表を作る(画像: &実行結果, 色: [u8; 3]) -> Vec<bool> {
    画像
        .rgba8
        .chunks_exact(4)
        .map(|画素| 画素[0] == 色[0] && 画素[1] == 色[1] && 画素[2] == 色[2])
        .collect()
}

/// 4近傍で繋がった画素を1つのかたまりにまとめる。深さ優先の探索を明示の作業列で行うのは、
/// 1つの球が数千画素になり、再帰では呼び出しの深さが画素数に比例するためである。
fn 繋がりで分ける(該当か: &[bool], 幅: usize, 高さ: usize) -> Vec<Vec<usize>> {
    let mut 訪問済み = vec![false; 該当か.len()];
    let mut かたまり一覧 = Vec::new();
    for 起点 in 0..該当か.len() {
        if !該当か[起点] || 訪問済み[起点] {
            continue;
        }
        訪問済み[起点] = true;
        let mut 作業列 = vec![起点];
        let mut かたまり = Vec::new();
        while let Some(添字) = 作業列.pop() {
            かたまり.push(添字);
            for 隣 in 四近傍(添字, 幅, 高さ) {
                if 該当か[隣] && !訪問済み[隣] {
                    訪問済み[隣] = true;
                    作業列.push(隣);
                }
            }
        }
        かたまり一覧.push(かたまり);
    }
    かたまり一覧
}

fn 四近傍(添字: usize, 幅: usize, 高さ: usize) -> Vec<usize> {
    let (x, y) = (添字 % 幅, 添字 / 幅);
    let mut 一覧 = Vec::with_capacity(4);
    if x > 0 {
        一覧.push(添字 - 1);
    }
    if x + 1 < 幅 {
        一覧.push(添字 + 1);
    }
    if y > 0 {
        一覧.push(添字 - 幅);
    }
    if y + 1 < 高さ {
        一覧.push(添字 + 幅);
    }
    一覧
}

fn 横位置の平均(かたまり: &[usize], 幅: usize) -> f64 {
    let 合計: f64 = かたまり.iter().map(|添字| 実数へ(添字 % 幅)).sum();
    合計 / 実数へ(かたまり.len())
}

fn 実数へ(値: usize) -> f64 {
    f64::from(u32::try_from(値).unwrap_or(u32::MAX))
}
