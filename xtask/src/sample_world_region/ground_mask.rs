//! 地面の画素を識別する領域マスク。受け取るのはライティングもポスト処理も空も外して撮った1枚、
//! 返すのは画素ごとに地面かどうかを持つ表である。
//!
//! ライティングとポスト処理を外した条件では、どの面もベースカラー係数をそのまま書き出す。地面は画像を1枚も持たない
//! 単一の材質であるため、地面の画素はすべて同じ1つの色になる。その色を画面下端の中央の見本区画から読み、
//! 同じ色の画素だけを地面と判定する。球も台座も小物も地面と違うベースカラーを宣言しているため、この一致で分かれる。
//!
//! 見本区画の全画素が同じ色であることを先に確かめる。初期カメラは固定されており、この区画には視点の手前の地面だけが写る。
//! 小物や台座がここへ入ってきたら「見本の区画が一色でない」で落ちるため、判定が黙って別の面の色を地面の色として採ることがない。

use crate::acceptance::読み戻し画像;

/// 地面の色を読む見本の区画の、画面の幅と高さに対する割合。
const 見本の左: f64 = 0.45;
const 見本の右: f64 = 0.55;
const 見本の上: f64 = 0.94;
const 見本の下: f64 = 0.99;

pub struct 地面マスク {
    地面か一覧: Vec<bool>,
    pub 地面画素数: u64,
}

impl 地面マスク {
    pub fn 作る(マスク: &読み戻し画像) -> Result<Self, String> {
        let 地面の色 = 見本区画の一色を読む(マスク)?;
        let mut 地面か一覧 = Vec::with_capacity(マスク.画素数());
        let mut 地面画素数 = 0_u64;
        for 添字 in 0..マスク.画素数() {
            let 地面か = マスク.添字の画素(添字) == 地面の色;
            地面画素数 += u64::from(地面か);
            地面か一覧.push(地面か);
        }
        if 地面画素数 == 0 {
            return Err("領域マスクから地面の画素が1つも取れなかった".to_string());
        }
        Ok(Self {
            地面か一覧, 地面画素数
        })
    }

    pub fn 地面か(&self, 添字: usize) -> bool {
        self.地面か一覧[添字]
    }

    pub fn 寸法が合うか(&self, 絵: &読み戻し画像) -> Result<(), String> {
        let 画素数 = 絵.画素数();
        if self.地面か一覧.len() != 画素数 {
            return Err(format!("領域マスクと絵の画素数が違う: {}と{画素数}", self.地面か一覧.len()));
        }
        Ok(())
    }
}

fn 見本区画の一色を読む(マスク: &読み戻し画像) -> Result<[u8; 3], String> {
    let x開始 = 割合を画素へ(見本の左, マスク.幅());
    let x終端 = 割合を画素へ(見本の右, マスク.幅());
    let y開始 = 割合を画素へ(見本の上, マスク.高さ());
    let y終端 = 割合を画素へ(見本の下, マスク.高さ());
    if x開始 >= x終端 || y開始 >= y終端 {
        return Err("地面の色を読む見本の区画が空になった".to_string());
    }
    let 代表色 = マスク.座標の画素(x開始, y開始);
    for y in y開始..y終端 {
        for x in x開始..x終端 {
            let 色 = マスク.座標の画素(x, y);
            if 色 != 代表色 {
                return Err(format!("地面の色を読む見本の区画が一色でない: {代表色:?}と{色:?}(画素{x},{y})"));
            }
        }
    }
    Ok(代表色)
}

fn 割合を画素へ(割合: f64, 画素数: usize) -> usize {
    let 実数 = 割合 * f64::from(u32::try_from(画素数).unwrap_or(u32::MAX));
    let mut 位置 = 0usize;
    while 位置 < 画素数 && f64::from(u32::try_from(位置 + 1).unwrap_or(u32::MAX)) <= 実数 {
        位置 += 1;
    }
    位置
}
