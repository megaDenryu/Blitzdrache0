//! 採取の読み取りの破れ: 採った絵と由来のファイルを読む段で破れうる前提を数え上げた型。
//!
//! 判定の破れと別の型にするのは、直す側が見る場所が違うためである。ここの破れはどれも採り直しか
//! 書式の食い違いで直るものであり、絵に写った陰影が退行したことは1つも意味しない。
//!
//! 「ファイルが無い」と「ファイルはあるが読めない」を別の枝で持つのは、前者が採取をまだ走らせていない印であり、
//! 後者が書き出しの書式が変わった印であるためである。

use std::fmt;
use std::path::PathBuf;

#[derive(Debug)]
pub(in crate::distant_view) enum 採取の読み取りの破れ {
    ファイルを読めなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    寸法の行に幅と高さが並んでいない {
        パス: PathBuf,
        本文: String,
    },
    寸法の綴りを数として読めない {
        パス: PathBuf,
        綴り: String,
    },
    画素数が桁あふれした {
        パス: PathBuf,
        幅: usize,
        高さ: usize,
    },
    寸法とバイト長が食い違う {
        名前: String,
        画素数: usize,
        色のバイト長: usize,
        深度のバイト長: usize,
    },
    採取の旗の行が無い {
        パス: PathBuf,
    },
    採取の旗に欄が無い {
        パス: PathBuf,
        欄: &'static str,
    },
    採取の旗の欄が入でも切でもない {
        パス: PathBuf,
        欄: &'static str,
        綴り: String,
    },
    由来に欄の記録が無い {
        名前: String,
        欄: &'static str,
    }, // 欄そのものを持たない由来。その欄を足す前に採った古い採取であり、要る段は採り直しを促す
}

impl fmt::Display for 採取の読み取りの破れ {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::ファイルを読めなかった { パス, 誤り } => write!(書き手, "{}を読めない: {誤り}", パス.display()),
            Self::寸法の行に幅と高さが並んでいない { パス, 本文 } => {
                write!(書き手, "{}に幅と高さが並んでいない: {本文}", パス.display())
            }
            Self::寸法の綴りを数として読めない { パス, 綴り } => {
                write!(書き手, "{}の寸法の綴り{綴り}を数として読めない", パス.display())
            }
            Self::画素数が桁あふれした { パス, 幅, 高さ } => {
                write!(書き手, "{}の寸法{幅}x{高さ}から画素数を求めると桁があふれる", パス.display())
            }
            Self::寸法とバイト長が食い違う {
                名前,
                画素数,
                色のバイト長,
                深度のバイト長,
            } => write!(
                書き手,
                "{名前}の寸法とバイト長が一致しない(画素数{画素数}・提示色{色のバイト長}バイト・最終深度{深度のバイト長}バイト)"
            ),
            Self::採取の旗の行が無い { パス } => {
                write!(書き手, "{}に採取の旗の行が無い。この名前を採り直す必要がある", パス.display())
            }
            Self::採取の旗に欄が無い { パス, 欄 } => write!(書き手, "{}の採取の旗に{欄}が無い", パス.display()),
            Self::採取の旗の欄が入でも切でもない { パス, 欄, 綴り } => {
                write!(書き手, "{}の採取の旗の{欄}がonでもoffでもない: {綴り}", パス.display())
            }
            Self::由来に欄の記録が無い { 名前, 欄 } => {
                write!(書き手, "{名前}の由来に{欄}の記録が無い。この名前を採り直す必要がある")
            }
        }
    }
}
