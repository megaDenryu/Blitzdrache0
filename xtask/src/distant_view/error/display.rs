//! 遠景構図の検収エラーを人が読む1文へ写すトレイト実装。枝ごとに、どの前提がどう破れたかを出す。
//! 実装を型の定義と分けるのは、外部トレイトの実装が型自身の持ち物とは別の軸であるためである。

use std::fmt;

use super::遠景構図の検収エラー;

impl fmt::Display for 遠景構図の検収エラー {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::引数が不正(引数) => {
                write!(書き手, "distant-viewの採取・診断・計画・判定の引数を1つだけ指定する必要がある: {引数}")
            }
            Self::構築が失敗した(理由) => write!(書き手, "{理由}"),
            Self::描画検収が失敗した(理由) => write!(書き手, "{理由}"),
            Self::由来を書けなかった { パス, 誤り } => write!(書き手, "{}へ由来を書けなかった: {誤り}", パス.display()),
            Self::再撮影が一致しない(形式) => write!(書き手, "同じ条件で再撮影した{形式}がバイト一致しない"),
            Self::構図契約が失敗した(理由) => write!(書き手, "遠景の固定構図が設計仕様を満たさない: {理由}"),
            Self::採取を読めなかった(破れ) => write!(書き手, "採取を読めなかった: {破れ}"),
            Self::判定が破れた(破れ) => write!(書き手, "{破れ}"),
        }
    }
}
