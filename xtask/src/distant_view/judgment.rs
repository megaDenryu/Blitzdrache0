//! 工程Dのreference/candidateを、近傍不変・遠景の許可域・深度・空隙の契約で比較する。

mod contour;
mod gap;
#[cfg(test)]
mod gap_tests;
mod image_pair;

use std::path::Path;

use image_pair::検収画像;

pub(super) fn 判定する(置き場: &Path) -> Result<String, String> {
    let 対照 = 検収画像::読む(置き場, "reference")?;
    let 候補 = 検収画像::読む(置き場, "candidate")?;
    対照.同じ寸法を課す(&候補)?;
    let 輪郭 = contour::輪郭を二画素広げる(&対照);
    let mut 近傍差 = 0_usize;
    let mut 許可外差 = 0_usize;
    let mut 遠景勝利 = 0_usize;
    let mut 背景から遠景 = 0_usize;
    for (添字, 輪郭内) in 輪郭.iter().copied().enumerate() {
        let 対照幾何 = 対照.深度[添字] > 0.0;
        let 候補幾何 = 候補.深度[添字] > 0.0;
        let 色差 = 対照.色画素(添字) != 候補.色画素(添字);
        let 深度差 = 対照.深度画素(添字) != 候補.深度画素(添字);
        if 対照幾何 && !輪郭内 && (色差 || 深度差) {
            近傍差 += 1;
        }
        if !輪郭内 && (色差 || 深度差) && (対照幾何 || !候補幾何) {
            許可外差 += 1;
        }
        if 対照幾何 && 候補幾何 && 候補.深度[添字] < 対照.深度[添字] && !輪郭内 {
            遠景勝利 += 1;
        }
        if !対照幾何 && 候補幾何 {
            背景から遠景 += 1;
        }
    }
    let 非有限 = 対照.非有限深度数() + 候補.非有限深度数();
    let 空隙 = gap::閉じた先読み縁の空隙画素を数える(&対照, &候補);
    if 近傍差 != 0 || 許可外差 != 0 || 遠景勝利 != 0 || 非有限 != 0 || 空隙 != 0 || 背景から遠景 == 0 {
        return Err(format!(
            "近傍差={近傍差} 許可外差={許可外差} 遠景勝利={遠景勝利} 非有限={非有限} 空隙={空隙} 背景→遠景={背景から遠景}"
        ));
    }
    Ok(format!(
        "近傍差0・許可外差0・遠景勝利0・非有限0・先読み縁空隙0、背景→遠景{背景から遠景}画素"
    ))
}
