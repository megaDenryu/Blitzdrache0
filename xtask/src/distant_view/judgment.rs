/// 影の距離区分の再配分の検査点。遠景の検査点と分けて呼ぶのは、空中遠近・遠景・影の変化を同じ比較へ混ぜないためである。
pub(super) fn 影を判定する(置き場: &Path) -> Result<String, 遠景構図の検収エラー> {
    shadow_stage::判定する(置き場)
}

/// 散布の検査点。遠景と影の検査点と分けて呼ぶのは、空中遠近・遠景・影・散布の変化を同じ比較へ混ぜないためである。
pub(super) fn 散布を判定する(置き場: &Path) -> Result<String, 遠景構図の検収エラー> {
    scatter_stage::判定する(置き場)
}

pub(super) fn 判定する(置き場: &Path) -> Result<String, 遠景構図の検収エラー> {
    let 主判定 = 主判定を課す(置き場)?;
    let 有界検査 = 有界検査を課す(置き場)?;
    Ok(format!("主判定(後処理なし)は{主判定}、有界検査(後処理あり)は{有界検査}"))
}

/// 陰影そのものの不変を課す段。滲みが混ざらないため、近傍の色差は1画素も許さない。
fn 主判定を課す(置き場: &Path) -> Result<String, 遠景構図の検収エラー> {
    let (対照, 候補, 区分) = 対を読む(置き場, "reference_no_post", "candidate_no_post", false)?;
    let 幾何 = 幾何の実測::測る(&対照, &候補, &区分).課す()?;
    let 色 = 許可域外の色差::集める(&対照, &候補, &区分.許可域の外の一覧()).一画素も無いことを課す(&区分.近傍の一覧())?;
    Ok(format!("{幾何}・{色}"))
}

/// 出荷される構成のまま課す段。差が残ること自体は認め、滲みとして説明できる形に収まっていることを見る。
fn 有界検査を課す(置き場: &Path) -> Result<String, 遠景構図の検収エラー> {
    let (対照, 候補, 区分) = 対を読む(置き場, "reference", "candidate", true)?;
    let 幾何 = 幾何の実測::測る(&対照, &候補, &区分).課す()?;
    let 発生源: Vec<bool> = (0..区分.画素数()).map(|添字| 区分.遠景が背景を置き換えたか(添字)).collect();
    let 足跡 = にじみの足跡::求める(対照.幅, 対照.高さ, &発生源);
    // 遠景は明るい空を暗い地形へ置き換えるため、発生源の向きは暗化に決まっている。散布の検査点は
    // 地面より明るい岩も暗い木も置くため、向きを発生源の平均輝度の動きから決める。
    let 色 = 許可域外の色差::集める(&対照, &候補, &区分.許可域の外の一覧()).有界であることを課す(&足跡, 色の動く向き::暗化)?;
    Ok(format!("{幾何}・{色}"))
}

/// 絵を読む前に採取の旗を照合する。段が要る構成と違う絵を突き合わせても、絵からはその食い違いが分からない。
fn 対を読む(
    置き場: &Path,
    対照名: &str,
    候補名: &str,
    後処理を使うか: bool,
) -> Result<(検収画像, 検収画像, 画素の区分), 遠景構図の検収エラー> {
    for 名前 in [対照名, 候補名] {
        let 旗 = 採取の旗::由来ファイルから読む(置き場, 名前)?;
        採取の後処理の判定名(名前, "この検査点は後処理の有無で対を分けて課す")
            .綴りの一致を課す(後処理の有無の綴り(旗.後処理を使うか()), 後処理の有無の綴り(後処理を使うか))?;
    }
    let 対照 = 検収画像::読む(置き場, 対照名)?;
    let 候補 = 検収画像::読む(置き場, 候補名)?;
    対照.同じ寸法を課す(&候補)?;
    let 区分 = 画素の区分::求める(&対照, &候補);
    Ok((対照, 候補, 区分))
}
