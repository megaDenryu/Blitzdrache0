//! 大規模世界の固定構図を提示色と深度で2回ずつ採り、再撮影の一致を判定する工程。

use std::path::PathBuf;

use super::error::遠景構図の検収エラー;
use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 書き出しの形式, 検収の実行名
};

const 枚数: 描画フレーム数 = 描画フレーム数::生成する(360);

pub(super) fn 実行環境を作る(出力先: PathBuf) -> Result<描画検収の実行環境, 遠景構図の検収エラー> {
    let アセット = crate::game_fox_tour::map_generation_check::大規模世界の計測入力パス();
    Ok(描画検収の実行環境::作る(
        アプリの起こし方::構築済みのリリース版を直に起動する,
        実行時アセットルート::パスから生成する(アセット),
        出力先,
    )?)
}

pub(super) fn 固定構図を二回採る(
    環境: &描画検収の実行環境, 条件: &super::plan::採取条件
) -> Result<String, 遠景構図の検収エラー> {
    let 名前 = 条件.名前;
    let 指定 = 起動指定(条件);
    let 色名 = 実行名(&format!("{名前}_color"))?;
    let 色の再撮影名 = 実行名(&format!("{名前}_color_repeat"))?;
    let 色 = 環境.描いて読み戻す(色名.clone(), &指定)?;
    let 色の再撮影 = 環境.描いて読み戻す(色の再撮影名, &指定)?;
    let 構図 = super::plan::構図を検査する(色.報告()).map_err(遠景構図の検収エラー::構図契約が失敗した)?;
    let 再撮影の構図 = super::plan::構図を検査する(色の再撮影.報告()).map_err(遠景構図の検収エラー::構図契約が失敗した)?;
    if 構図 != 再撮影の構図 {
        return Err(遠景構図の検収エラー::構図契約が失敗した(
            "同じ条件の色採取で構図の実測が一致しない".to_string(),
        ));
    }
    if 色.画像().バイト列() != 色の再撮影.画像().バイト列() {
        return Err(遠景構図の検収エラー::再撮影が一致しない("提示色"));
    }
    let 深度名 = 実行名(&format!("{名前}_depth"))?;
    let 深度の再撮影名 = 実行名(&format!("{名前}_depth_repeat"))?;
    let 深度報告 = 環境.書き出させて報告を採る(深度名.clone(), &指定, 書き出しの形式::最終深度)?;
    let 深度の再撮影報告 = 環境.書き出させて報告を採る(深度の再撮影名.clone(), &指定, 書き出しの形式::最終深度)?;
    for 報告 in [&深度報告, &深度の再撮影報告] {
        if super::plan::構図を検査する(報告).map_err(遠景構図の検収エラー::構図契約が失敗した)? != 構図 {
            return Err(遠景構図の検収エラー::構図契約が失敗した(
                "色と深度の採取で構図の実測が一致しない".to_string(),
            ));
        }
    }
    let 深度 = 環境.同じ置き場の書き出しのバイト列を読む(深度名, 書き出しの形式::最終深度)?;
    let 深度の再撮影 = 環境.同じ置き場の書き出しのバイト列を読む(深度の再撮影名, 書き出しの形式::最終深度)?;
    if 深度 != 深度の再撮影 {
        return Err(遠景構図の検収エラー::再撮影が一致しない("最終深度"));
    }
    let 絵 = 環境.同じ置き場の書き出しを目視用の絵へ変換する(色名)?;
    Ok(format!(
        "{構図}、提示色{}画素と最終深度が再撮影とバイト一致し、絵を{}へ保存した",
        色.画像().画素数(),
        絵.display()
    ))
}

fn 起動指定(条件: &super::plan::採取条件) -> アプリの起動指定 {
    let mut 指定 = アプリの起動指定::シーンと枚数を決める(crate::fox_tour_launch::シーン名, 枚数)
        .選択肢を足す("--streaming")
        .値を持つ選択肢を足す("--streaming-preload-radius", "8")
        .値を持つ選択肢を足す("--streaming-ram-limit", "536870912")
        .値を持つ選択肢を足す("--streaming-vram-limit", "536870912")
        .値を持つ選択肢を足す("--streaming-loader-workers", "1")
        .値を持つ選択肢を足す("--game", "fox_tour")
        .値を持つ選択肢を足す("--camera-yaw", "180")
        .値を持つ選択肢を足す("--camera-pitch", "-11.0107")
        .値を持つ選択肢を足す("--time-of-day", "43200")
        .選択肢を足す("--no-taa")
        .選択肢を足す("--no-auto-exposure")
        .値を持つ選択肢を足す("--depth-prepass", "equal");
    if 条件.ssaoを使わない {
        指定 = 指定.選択肢を足す("--no-ssao");
    }
    if 条件.遠景影を使わない {
        指定 = 指定.選択肢を足す("--no-distant-shadow");
    }
    if 条件.後処理を使わない {
        指定 = 指定.選択肢を足す("--no-post");
    }
    if 条件.影可視度を可視化する {
        指定 = 指定.選択肢を足す("--debug-shadow-loss");
    }
    if 条件.明示境界を使わない {
        指定 = 指定.選択肢を足す("--no-explicit-shadow-bands");
    }
    指定
}

fn 実行名(名前: &str) -> Result<検収の実行名, 遠景構図の検収エラー> {
    Ok(検収の実行名::生成する(名前)?)
}
