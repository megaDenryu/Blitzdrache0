//! 深度だけで決まる不変条件を両方の対へ課す工程。受け取るのは対照と候補の検収画像と画素の区分、
//! 返すのは満たしたときの要約か、破れた条件を数で名指しした失敗である。
//!
//! 課すのは、近傍の深度が1バイトも動かないこと・遠景が近傍を隠さないこと・深度が全画素で有限であること・
//! 先読みの縁に空隙が無いこと・遠景が実際に背景へ現れていることの5つである。
//!
//! 後処理は深度画像へ触れないため、この契約は後処理ありの対でも同じ厳しさで通らなければならない。
//! 主判定の対(後処理なし)でだけ課すと、実際に出荷される絵の幾何を誰も検査しないまま通ることになる。

use super::gap;
use super::image_pair::検収画像;
use super::pixel_class::画素の区分;

pub(super) fn 課す(対照: &検収画像, 候補: &検収画像, 区分: &画素の区分) -> Result<String, String> {
    let mut 近傍の深度差 = 0_usize;
    let mut 遠景勝利 = 0_usize;
    let mut 背景から遠景 = 0_usize;
    for 添字 in 0..区分.画素数() {
        if 区分.近傍か(添字) && 対照.深度画素(添字) != 候補.深度画素(添字) {
            近傍の深度差 += 1;
        }
        if 区分.近傍か(添字) && 区分.候補幾何か(添字) && 候補.深度[添字] < 対照.深度[添字] {
            遠景勝利 += 1;
        }
        if 区分.遠景が背景を置き換えたか(添字) {
            背景から遠景 += 1;
        }
    }
    let 非有限 = 対照.非有限深度数() + 候補.非有限深度数();
    let 空隙 = gap::閉じた先読み縁の空隙画素を数える(対照, 候補);
    if 近傍の深度差 != 0 || 遠景勝利 != 0 || 非有限 != 0 || 空隙 != 0 || 背景から遠景 == 0 {
        return Err(format!(
            "近傍の深度差={近傍の深度差} 遠景勝利={遠景勝利} 非有限={非有限} 空隙={空隙} 背景→遠景={背景から遠景}"
        ));
    }
    Ok(format!("背景→遠景{背景から遠景}画素"))
}
