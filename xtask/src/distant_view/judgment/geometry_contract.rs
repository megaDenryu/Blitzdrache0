//! 深度だけで決まる不変条件を両方の対へ課す工程。受け取るのは対照と候補の検収画像と画素の区分、
//! 返すのは満たしたときの要約か、破れた条件を数で名指した判定の破れである。
//!
//! 課すのは、近傍の深度が1バイトも動かないこと・遠景が近傍を隠さないこと・深度が全画素で有限であること・
//! 先読みの縁に空隙が無いこと・遠景が実際に背景へ現れていることの5つである。
//!
//! 後処理は深度画像へ触れないため、この契約は後処理ありの対でも同じ厳しさで通らなければならない。
//! 主判定の対(後処理なし)でだけ課すと、実際に出荷される絵の幾何を誰も検査しないまま通ることになる。

use super::gap;
use super::image_pair::検収画像;
use super::pixel_class::画素の区分;
use super::verdict_names::幾何契約の判定名;
use crate::acceptance::判定の破れ;

/// 5つの条件が読む数の実測。5つを1つの型へ束ねるのは、どれか1つが破れたときに残りの数も
/// 同じ行で読めるよう、判定の名前が全部を名指すためである。
pub(super) struct 幾何の実測 {
    近傍の深度差: usize,
    遠景勝利: usize,
    非有限: usize,
    空隙: usize,
    背景から遠景: usize,
}

impl 幾何の実測 {
    pub(super) fn 測る(対照: &検収画像, 候補: &検収画像, 区分: &画素の区分) -> Self {
        let mut 実測 = Self {
            近傍の深度差: 0,
            遠景勝利: 0,
            非有限: 対照.非有限深度数() + 候補.非有限深度数(),
            空隙: gap::閉じた先読み縁の空隙画素を数える(対照, 候補),
            背景から遠景: 0,
        };
        for 添字 in 0..区分.画素数() {
            if 区分.近傍か(添字) && 対照.深度画素(添字) != 候補.深度画素(添字) {
                実測.近傍の深度差 += 1;
            }
            if 区分.近傍か(添字) && 区分.候補幾何か(添字) && 候補.深度[添字] < 対照.深度[添字] {
                実測.遠景勝利 += 1;
            }
            if 区分.遠景が背景を置き換えたか(添字) {
                実測.背景から遠景 += 1;
            }
        }
        実測
    }

    pub(super) fn 課す(&self) -> Result<String, 判定の破れ> {
        let 綴り = self.綴り();
        幾何契約の判定名("近傍の深度が動いた画素", &綴り).零件であることを課す(self.近傍の深度差)?;
        幾何契約の判定名("遠景が近傍を隠した画素", &綴り).零件であることを課す(self.遠景勝利)?;
        幾何契約の判定名("有限でない深度の画素", &綴り).零件であることを課す(self.非有限)?;
        幾何契約の判定名("閉じた先読みの縁の空隙の画素", &綴り).零件であることを課す(self.空隙)?;
        if self.背景から遠景 == 0 {
            return Err(幾何契約の判定名("背景から遠景へ変わった画素", &綴り).あるはずのものが無い破れ());
        }
        Ok(format!("背景→遠景{}画素", self.背景から遠景))
    }

    fn 綴り(&self) -> String {
        format!(
            "近傍の深度差={} 遠景勝利={} 非有限={} 空隙={} 背景→遠景={}",
            self.近傍の深度差, self.遠景勝利, self.非有限, self.空隙, self.背景から遠景
        )
    }
}
