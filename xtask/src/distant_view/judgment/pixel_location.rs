//! 判定の名前が画素を名指すときの位置。受け取るのは画素の番号と画像の幅、返すのは画面上の横と縦の位置である。
//!
//! 番号のままでは、破れを読んだ人が絵のどこを見ればよいか決められない。横と縦へ分けて述べる。
//! 番号と幅を裸のusizeのまま名前の組み立てへ配ると、取り違えても型が通り、別の画素を名指したまま気づけない。

use std::fmt;

use crate::acceptance::{画像の幅, 画素の横位置, 画素の番号, 画素の縦位置};

#[derive(Clone, Copy)]
pub(super) struct 画素の位置 {
    横: 画素の横位置,
    縦: 画素の縦位置,
}

impl 画素の位置 {
    /// 前提: 幅は1以上である。幅0の絵は画素を1つも持たないため、この口へ番号が来ることがない。
    pub(super) fn 番号と幅から求める(番号: 画素の番号, 幅: 画像の幅) -> Self {
        Self {
            横: 画素の横位置::生成する(番号.値() % 幅.画素数()),
            縦: 画素の縦位置::生成する(番号.値() / 幅.画素数()),
        }
    }
}

impl fmt::Display for 画素の位置 {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(書き手, "画素(横{}・縦{})", self.横.値(), self.縦.値())
    }
}
