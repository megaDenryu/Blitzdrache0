//! 遠景の検査点が破れたときの文面の組み立て。受け取るのは破れた対象と同時に読ませたい実測、返すのは判定の名前である。
//!
//! 幾何の5つの条件が実測を丸ごと名前へ入れるのは、1つが破れたときに残り4つの数も同じ行で読めるようにするためである。
//! どれか1つだけが動いたのか幾何が全体として崩れたのかを、その場で切り分けられる。

use crate::acceptance::判定の名前;

/// 突き合わせる2枚は同じ寸法でなければならない。違えば同じ添字が2枚で別の位置を指す。
pub(super) const 突き合わせる二枚の絵の寸法: 判定の名前 = 判定の名前::定数から生成する("突き合わせる2枚の絵の寸法");

pub(super) fn 幾何契約の判定名(測るもの: &str, 幾何の実測の綴り: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{測るもの}(幾何の実測は{幾何の実測の綴り}である)"))
}

pub(super) fn 採取の後処理の判定名(採取の名前: &str, この段が要る理由: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{採取の名前}の採取の後処理の有無({この段が要る理由})"))
}

/// 由来ファイルの旗と絵の突き合わせ方を同じ綴りで語るための、後処理の有無の1語。
pub(super) fn 後処理の有無の綴り(使うか: bool) -> &'static str {
    if 使うか { "あり" } else { "なし" }
}
