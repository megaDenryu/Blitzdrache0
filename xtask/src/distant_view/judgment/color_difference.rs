//! 許可域の外へ出た色差の一覧と、それへ課す厳しさ。受け取るのは対照と候補の検収画像と画素の区分、
//! 返すのは差の一覧と、課した条件を満たしたときの要約である。
//!
//! 一覧を持つ型にするのは、同じ差の集合へ厳しさの違う判定を当てるためである。主判定は「1画素も無いこと」を、
//! 陰影の段は「向きだけ」を、にじみの段は「足跡の内側(発生源の変化が一方向なら向きも)」を課す。遠景の段が
//! 課す階調の上限だけは、根拠が遠景の構図に固有であるため`distant_view_bound`が持つ。
//! 集める規則を段ごとに割ると、別の画素集合を数えていても要約の見た目だけは揃ってしまう。

mod change_direction;
mod changed_pixel;
mod distant_view_bound;
mod distribution;
mod verdict_names;

pub(in crate::distant_view) use change_direction::{発生源の変化の向き, 色の動く向き};

use changed_pixel::変化した画素;
use verdict_names::{発生源からの距離の判定名, 許可域外の色差の判定名, 逆へ動いた画素の判定名};

use super::bloom_footprint::にじみの足跡;
use super::image_pair::検収画像;
use super::pixel_location::画素の位置;
use crate::acceptance::{判定の破れ, 画像の幅, 画素の番号};

pub(super) struct 許可域外の色差 {
    幅: 画像の幅,
    一覧: Vec<変化した画素>,
}

impl 許可域外の色差 {
    /// 許可域の外かを真偽の並びで受け取るのは、遠景の検査点と散布の検査点が別の許可域を持つためである。
    /// 集める規則そのものは同じであり、2つに割ると別の画素集合を数えていても要約の見た目だけは揃う。
    pub(super) fn 集める(対照: &検収画像, 候補: &検収画像, 許可域の外: &[bool]) -> Self {
        let 一覧 = (0..許可域の外.len())
            .filter(|添字| 許可域の外[*添字])
            .filter_map(|添字| 変化した画素::求める(対照, 候補, 添字))
            .collect();
        Self {
            幅: 対照.画像の幅(), 一覧
        }
    }

    /// 主判定。近傍チャンクの幾何画素は深度も色も動かないという第5段階の検査点4の要求そのものである。
    pub(super) fn 一画素も無いことを課す(&self, 近傍: &[bool]) -> Result<String, 判定の破れ> {
        let 近傍差 = self.一覧.iter().filter(|画素| 近傍[画素.添字]).count();
        let 最大階調差 = self.一覧.iter().map(|画素| 画素.最大階調差).max().unwrap_or(0);
        許可域外の色差の判定名(近傍差, &self.位置の綴り(self.一覧.first()), 最大階調差).零件であることを課す(self.一覧.len())?;
        Ok("近傍差0・許可域外の色差0".to_string())
    }

    /// 向きだけを課す段。差の大きさも発生源からの距離も見ない。機構が向きしか決めないときに使う。
    /// 不透明な物体を地面へ置くことは、その物体が覆っていない面へ届く光を減らすことしかできない。
    pub(super) fn 向きだけを課す(&self, 期待する向き: 色の動く向き) -> Result<String, 判定の破れ> {
        self.逆へ動いた画素が無いことを課す(期待する向き)?;
        Ok(format!("許可域の外の色差{}画素が全て{}である", self.一覧.len(), 期待する向き.綴り()))
    }

    /// にじみの段。にじみが1画素の変化を運べる範囲に収まっていることを課し、発生源の変化が一方向のときだけ
    /// 向きも課す。階調の大きさを課さないのは、にじみが撒く光の減り方が場面の明るさに比例し、上限を機構から
    /// 導く式が無いためである。
    /// 参照: `_doc/設計/大規模世界の生成と遠景.md`「第6段階」
    pub(super) fn 足跡の内側であることを課す(
        &self,
        足跡: &にじみの足跡,
        発生源の向き: 発生源の変化の向き,
    ) -> Result<String, 判定の破れ> {
        if let 発生源の変化の向き::一方向(期待する向き) = 発生源の向き {
            self.逆へ動いた画素が無いことを課す(期待する向き)?;
        }
        self.発生源からの距離の上限を課す(足跡)?;
        Ok(format!(
            "許可域外の色差{}画素が発生源から{}画素以内に収まった",
            self.一覧.len(),
            足跡.上限()
        ))
    }

    fn 逆へ動いた画素が無いことを課す(&self, 期待する向き: 色の動く向き) -> Result<(), 判定の破れ> {
        let 逆へ動いたか = |画素: &&変化した画素| 期待する向き.逆へ動いたか(画素.明化を含むか, 画素.暗化を含むか);
        逆へ動いた画素の判定名(期待する向き.綴り(), &self.位置の綴り(self.一覧.iter().find(逆へ動いたか)))
            .零件であることを課す(self.一覧.iter().filter(逆へ動いたか).count())
    }

    /// 最も遠い差だけへ上限を課すのは、それが上限を守るなら残り全部も守るためである。1件ずつ課すと、
    /// 破れの文面が「たまたま最初に見つかった画素」を名指すことになる。
    fn 発生源からの距離の上限を課す(&self, 足跡: &にじみの足跡) -> Result<(), 判定の破れ> {
        if let Some(画素) = self.一覧.iter().max_by_key(|画素| 足跡.発生源からの距離(画素.添字)) {
            発生源からの距離の判定名(self.位置(画素)).上限を課す(足跡.発生源からの距離(画素.添字), 足跡.上限())?;
        }
        Ok(())
    }

    fn 位置(&self, 画素: &変化した画素) -> 画素の位置 {
        画素の位置::番号と幅から求める(画素の番号::生成する(画素.添字), self.幅)
    }

    fn 位置の綴り(&self, 画素: Option<&変化した画素>) -> String {
        画素.map_or_else(|| "無し".to_string(), |画素| self.位置(画素).to_string())
    }
}
