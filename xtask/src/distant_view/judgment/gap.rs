//! 候補の背景を4連結成分へ分け、画面外の空と繋がらない先読み縁の穴だけを数える。
//!
//! **この分類が意味を持つのは遠景の検査点のA/Bだけである。** 「対照で背景・候補で幾何」を遠景と読むのは、
//! その対が遠景を焼かない実行と焼く実行だからである。散布の検査点のA/Bでは同じ条件が「散布が空を背に立った画素」を
//! 指すため、丘の上の個体が作る空の窪みを先読みの縁の穴として数えてしまう(2026-08-16に2画素で実測した)。
//! 散布の検査点はこの工程を使わない。
//!
//! 空と繋がるかを上辺だけで見るのは、画面の左右と下の辺へ届く背景が「画面外の空」とは限らないためである。
//! 固定構図では地平線が画面の上3分の1にあり、その下は地面が埋める。先読みの縁の穴が横へ長く伸びて左右の辺まで
//! 届くことも、手前まで下りて下辺へ届くこともあり、それらを画面外の空と読むと実在の穴を見逃す。
//! 上辺は水平線より上であり、そこへ届く背景は空へ繋がっている。

use std::collections::VecDeque;

use super::image_pair::検収画像;

/// 空隙の実測。件数だけでなく成分の数と最初の画素の添字を持つのは、破れたときに「どこの何画素か」を
/// 見に行けるようにするためである。件数だけでは、1つの穴か散らばった点かも、画面のどこかも分からない。
pub(super) struct 空隙の実測 {
    pub(super) 画素数: usize,
    pub(super) 成分数: usize,
    pub(super) 最初の画素: Option<usize>,
}

pub(super) fn 閉じた先読み縁の空隙を測る(対照: &検収画像, 候補: &検収画像) -> 空隙の実測 {
    let mut 訪問済み = vec![false; 候補.画素数()];
    let mut 実測 = 空隙の実測 {
        画素数: 0,
        成分数: 0,
        最初の画素: None,
    };
    for 始点 in 0..候補.画素数() {
        if 訪問済み[始点] || 候補.深度[始点] != 0.0 {
            continue;
        }
        let 成分 = 背景成分を辿る(対照, 候補, 始点, &mut 訪問済み);
        if !成分.上辺へ接する && 成分.近傍あり && 成分.遠景あり {
            実測.画素数 += 成分.画素数;
            実測.成分数 += 1;
            実測.最初の画素.get_or_insert(始点);
        }
    }
    実測
}

struct 背景成分 {
    画素数: usize,
    上辺へ接する: bool, // 上辺の外は空であり、そこへ繋がる背景は先読みの縁の穴ではない
    近傍あり: bool,
    遠景あり: bool,
}

fn 背景成分を辿る(対照: &検収画像, 候補: &検収画像, 始点: usize, 訪問済み: &mut [bool]) -> 背景成分 {
    let mut 待ち = VecDeque::from([始点]);
    訪問済み[始点] = true;
    let mut 結果 = 背景成分 {
        画素数: 0,
        上辺へ接する: false,
        近傍あり: false,
        遠景あり: false,
    };
    while let Some(添字) = 待ち.pop_front() {
        結果.画素数 += 1;
        let (x, y) = (添字 % 候補.幅, 添字 / 候補.幅);
        結果.上辺へ接する |= y == 0;
        for 隣 in 四近傍(候補.幅, 候補.高さ, x, y) {
            if 候補.深度[隣] == 0.0 {
                if !訪問済み[隣] {
                    訪問済み[隣] = true;
                    待ち.push_back(隣);
                }
            } else if 対照.深度[隣] > 0.0 {
                結果.近傍あり = true;
            } else {
                結果.遠景あり = true;
            }
        }
    }
    結果
}

fn 四近傍(幅: usize, 高さ: usize, x: usize, y: usize) -> impl Iterator<Item = usize> {
    let mut 一覧 = [None; 4];
    一覧[0] = (x > 0).then_some(y * 幅 + x.saturating_sub(1));
    一覧[1] = (x + 1 < 幅).then_some(y * 幅 + x + 1);
    一覧[2] = (y > 0).then_some(y.saturating_sub(1) * 幅 + x);
    一覧[3] = (y + 1 < 高さ).then_some((y + 1) * 幅 + x);
    一覧.into_iter().flatten()
}
