//! 散布の検査点で画素を区分し、差が出てよい許可域を決める工程。受け取るのは対照と候補の検収画像、
//! 返すのは画素ごとの区分である。
//!
//! 遠景の区分と別に持つのは、変わる場所の形が違うためである。遠景は背景を幾何へ置き換えるため区分の鍵が
//! 「対照で背景か」であるのに対し、散布は地面の手前へ物を置くため、対照も候補も幾何のまま深度だけが動く。
//! 遠景の区分をそのまま当てると、散布が覆った画素が「近傍の幾何画素」に数えられ、不変を課す先が
//! 変わってよい場所そのものになる。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「第6段階」

use super::contour;
use super::image_pair::検収画像;

pub(super) struct 散布の画素の区分 {
    対照幾何: Vec<bool>,
    候補幾何: Vec<bool>,
    散布が覆った: Vec<bool>,
    免除: Vec<bool>,
}

impl 散布の画素の区分 {
    /// 散布が覆った画素は「対照でも候補でも幾何であり、深度のバイト列が動いた画素」である。逆向き深度では
    /// 手前ほど値が大きく、散布物は地面の手前にしか現れないため、この集合がそのまま散布物の写った領域になる。
    /// 免除はその領域を2画素広げた帯であり、標本の位置の丸めで縁が1画素ぶん動くぶんを不変の要求から外す。
    pub(super) fn 求める(対照: &検収画像, 候補: &検収画像) -> Self {
        let 対照幾何: Vec<bool> = (0..対照.画素数()).map(|添字| 対照.深度[添字] > 0.0).collect();
        let 候補幾何: Vec<bool> = (0..候補.画素数()).map(|添字| 候補.深度[添字] > 0.0).collect();
        let 散布が覆った: Vec<bool> = (0..対照.画素数())
            .map(|添字| 対照幾何[添字] && 候補幾何[添字] && 対照.深度画素(添字) != 候補.深度画素(添字))
            .collect();
        let 免除 = contour::印を二画素広げる(対照.幅, 対照.高さ, &散布が覆った);
        Self {
            対照幾何,
            候補幾何,
            散布が覆った,
            免除,
        }
    }

    pub(super) fn 画素数(&self) -> usize {
        self.免除.len()
    }

    pub(super) fn 対照幾何か(&self, 添字: usize) -> bool {
        self.対照幾何[添字]
    }

    pub(super) fn 候補幾何か(&self, 添字: usize) -> bool {
        self.候補幾何[添字]
    }

    pub(super) fn 散布が覆ったか(&self, 添字: usize) -> bool {
        self.散布が覆った[添字]
    }

    pub(super) fn 散布が覆った一覧(&self) -> &[bool] {
        &self.散布が覆った
    }

    /// 差が出てよい範囲の外。散布が覆った画素と、その周りの免除帯だけが許可域である。
    pub(super) fn 許可域の外の一覧(&self) -> Vec<bool> {
        (0..self.画素数()).map(|添字| !self.免除[添字] && !self.散布が覆った[添字]).collect()
    }

    /// 対照に幾何があり、散布に覆われても免除帯にも入っていない画素。散布が触っていない地面である。
    pub(super) fn 近傍の一覧(&self) -> Vec<bool> {
        (0..self.画素数())
            .map(|添字| self.対照幾何[添字] && !self.免除[添字] && !self.散布が覆った[添字])
            .collect()
    }
}
