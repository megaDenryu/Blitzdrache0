//! 散布の検査点で画素を区分し、差が出てよい許可域を決める工程。受け取るのは対照と候補の検収画像、
//! 返すのは画素ごとの区分である。
//!
//! 遠景の区分と別に持つのは、変わる場所の形が違うためである。遠景は背景を幾何へ置き換えるため区分の鍵が
//! 「対照で背景か」であるのに対し、散布は地面の手前へ物を置くため、対照も候補も幾何のまま深度だけが動く画素が
//! 主になる。遠景の区分をそのまま当てると、散布が現れた画素が「近傍の幾何画素」に数えられ、
//! 不変を課す先が変わってよい場所そのものになる。
//!
//! **散布が現れた画素は2つの形を取る。** 1つは地面の手前へ立って深度だけを動かす形であり、もう1つは
//! 丘の上の個体が地平線より上へ出て空を背に立つ形である。後者は対照で背景・候補で幾何になる。
//! 2026-08-16の実測で後者が153画素あり、親が絵を起こして正当な見え方であることを確定した。
//! したがって許可域は両方を含む。片方だけを許可域にすると、空を背に立った個体の色が「許可域の外の色差」として
//! 数えられ、正当な絵が落ちる。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「第6段階」

use super::contour;
use super::image_pair::検収画像;

pub(super) struct 散布の画素の区分 {
    対照幾何: Vec<bool>,
    候補幾何: Vec<bool>,
    散布が現れた: Vec<bool>,
    免除: Vec<bool>,
}

impl 散布の画素の区分 {
    /// 免除は散布が現れた領域を2画素広げた帯であり、標本の位置の丸めで縁が1画素ぶん動くぶんを
    /// 不変の要求から外す。
    pub(super) fn 求める(対照: &検収画像, 候補: &検収画像) -> Self {
        let 対照幾何: Vec<bool> = (0..対照.画素数()).map(|添字| 対照.深度[添字] > 0.0).collect();
        let 候補幾何: Vec<bool> = (0..候補.画素数()).map(|添字| 候補.深度[添字] > 0.0).collect();
        let 散布が現れた: Vec<bool> = (0..対照.画素数())
            .map(|添字| 候補幾何[添字] && (!対照幾何[添字] || 対照.深度画素(添字) != 候補.深度画素(添字)))
            .collect();
        let 免除 = contour::印を二画素広げる(対照.幅, 対照.高さ, &散布が現れた);
        Self {
            対照幾何,
            候補幾何,
            散布が現れた,
            免除,
        }
    }

    pub(super) fn 画素数(&self) -> usize {
        self.免除.len()
    }

    pub(super) fn 対照幾何か(&self, 添字: usize) -> bool {
        self.対照幾何[添字]
    }

    pub(super) fn 候補幾何か(&self, 添字: usize) -> bool {
        self.候補幾何[添字]
    }

    pub(super) fn 散布が現れた一覧(&self) -> &[bool] {
        &self.散布が現れた
    }

    /// 差が出てよい範囲の外。散布が現れた画素と、その周りの免除帯だけが許可域である。
    pub(super) fn 許可域の外の一覧(&self) -> Vec<bool> {
        (0..self.画素数()).map(|添字| !self.免除[添字] && !self.散布が現れた[添字]).collect()
    }

    /// 対照に幾何があり、散布にも免除帯にも触れていない画素。散布が触っていない地面である。
    pub(super) fn 近傍の一覧(&self) -> Vec<bool> {
        (0..self.画素数())
            .map(|添字| self.対照幾何[添字] && !self.免除[添字] && !self.散布が現れた[添字])
            .collect()
    }
}
