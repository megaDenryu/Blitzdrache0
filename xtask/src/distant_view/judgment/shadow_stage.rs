//! 影の距離区分を再配分した前後を突き合わせる検査点。受け取るのは採取の置き場、返すのは要約か破れた条件である。
//!
//! 遠景の検査点と契約が逆を向く。遠景を足した対では背景が遠景へ変わることを要求したが、影の再配分は幾何を1つも
//! 動かさない。したがって全画素の深度のバイト一致を課す。深度が全画素で一致すれば幾何マスクも一致する
//! (幾何の有無は深度が0より大きいかで決まる)ため、マスクを別に数えずこの1つで両方を課す。
//!
//! 色の変化が影に由来することは2つの規則で確かめる。**向きの規則**は、記録された影可視度が動いた画素で、
//! 色のどのチャンネルも可視度と逆の向きへ動かないことを課す。影が薄れれば明るくなり、濃くなれば暗くなる。
//! **帰属の規則**は、2階調以上動いた色差がすべて記録の動きを伴うことを課す。
//!
//! **1階調の色差に記録の動きを求めない。** 診断は影可視度を8ビットへ符号化して運ぶため、1エンコード段より
//! 細かい可視度の変化を表せない。とりわけ影可視度が1.0付近(遮蔽なし)の画素では赤が255で飽和し、そこからの
//! わずかな変化は診断に一切現れない。それでも最終色は丸めの境界をまたいで1階調動きうる。8ビットの診断へ
//! それ自身より細かい分解能を求めることになるため、1階調は帰属の対象から外して数だけを要約へ出す。
//! 4つの採取の実測でも、記録の動きを伴わない色差は全件がちょうど1階調であり、2階調以上は1画素も無かった。
//! 分布は1階調と2階調の間で切れており、この線はそこに引いている。
//!
//! 4つとも同じバイナリで採る。対照側は`--no-explicit-shadow-bands`で再配分だけを切り、候補側は何も切らない。
//! 対照を再配分前のコミットの作業ツリーから採ると、比べている差に再配分以外のコミットの差が混ざり、
//! しかもその混ざりは絵からは見分けられない。由来の旗が4つの採取の条件を記録し、判定が読む前に照合する。
//!
//! 4つの採取をすべて後処理なしで採るのは、遠景の検査点で確かめた事実の適用である。光のにじみは画面内の
//! 演算子であり、影の変化は地平の帯と違って画面の広い範囲へ出るため、にじみの足跡の有界性でも救えない。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`第5段階の検査点5

mod capture_pair;
mod color_shift;

use std::path::Path;

use super::shadow_visibility::影可視度の対;
use color_shift::色の動き;

/// 帰属を求める色差の下限。これ未満の差は診断の符号化が表せない可視度の変化で説明がつく。
const 帰属を求める階調差: u16 = 2;

pub(in crate::distant_view) fn 判定する(置き場: &Path) -> Result<String, String> {
    let (対照, 候補) = capture_pair::色の対を読む(置き場)?;
    capture_pair::深度が全画素で一致することを課す(&対照, &候補)?;
    let 可視度 = 影可視度の対::読む(置き場)?;
    可視度.同じ画素数であることを課す(対照.画素数())?;

    let mut 記録なしの一階調 = 0_usize;
    for 添字 in 0..対照.画素数() {
        let Some(動き) = 色の動き::求める(&対照, &候補, 添字) else {
            continue;
        };
        match 可視度.明るくなる向きへ動いたか(添字) {
            Some(明るくなる向き) => 動き.可視度と同じ向きであることを課す(明るくなる向き, 添字, 対照.幅)?,
            None if 動き.最大階調差() >= 帰属を求める階調差 => {
                return Err(format!(
                    "{}が{}階調動いたのに影可視度の記録が動いていない。影の再配分では説明できない差である",
                    位置の綴り(添字, 対照.幅),
                    動き.最大階調差()
                ));
            }
            None => 記録なしの一階調 += 1,
        }
    }
    Ok(format!(
        "深度は全画素バイト一致し、影可視度の記録が動いたのは{}画素、色が動いた画素はすべて可視度と同じ向きで、記録の動きを伴わない色差は{記録なしの一階調}画素(すべて1階調)である",
        可視度.記録が動いた画素数()
    ))
}

pub(super) fn 位置の綴り(添字: usize, 幅: usize) -> String {
    format!("画素(横{}・縦{})", 添字 % 幅, 添字 / 幅)
}
