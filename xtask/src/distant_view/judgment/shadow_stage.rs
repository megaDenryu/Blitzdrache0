//! 影の距離区分を再配分した前後を突き合わせる検査点。受け取るのは採取の置き場、返すのは要約か破れた条件である。
//!
//! 遠景の検査点と契約が逆を向く。遠景を足した対では背景が遠景へ変わることを要求したが、影の再配分は幾何を1つも
//! 動かさない。したがってここでは全画素の深度のバイト一致を課す。深度が全画素で一致すれば幾何マスクも一致する
//! (幾何の有無は深度が0より大きいかで決まる)ため、マスクを別に数えずこの1つで両方を課す。
//! 変わってよいのは影可視度と、その結果として出た色だけである。
//!
//! 色差が影に由来することは、影の欠落計器の診断を対照と候補の両方で採り、「色が変わった画素が影可視度も
//! 変わった画素に含まれる」ことで確かめる。色だけを見ると、再配分と無関係な退行が影のせいに見えてしまう。
//! 空の画素も除外せずに突き合わせる。影の再配分は空を1画素も変えないため、変わったなら影以外の何かが動いている。
//!
//! 4つの採取をすべて後処理なしで採るのは、遠景の検査点で確かめた事実の適用である。光のにじみは画面内の演算子で
//! あり、絵のどこか1箇所が変われば離れた画素も量子化1段ぶん動く。影の変化は地平の帯と違って画面の広い範囲へ出るため、
//! にじみの足跡の有界性でも救えない。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`第5段階の検査点5

use std::path::Path;

use super::image_pair::検収画像;
use super::shadow_visibility::影可視度の対;
use crate::distant_view::provenance::採取の旗;

pub(in crate::distant_view) fn 判定する(置き場: &Path) -> Result<String, String> {
    let (対照, 候補) = 色の対を読む(置き場)?;
    深度が全画素で一致することを課す(&対照, &候補)?;
    let 可視度 = 影可視度の対::読む(置き場)?;
    可視度.同じ画素数であることを課す(対照.画素数())?;
    let 色が変わった画素: Vec<usize> = (0..対照.画素数()).filter(|添字| 対照.色画素(*添字) != 候補.色画素(*添字)).collect();
    let はみ出し = 色が変わった画素.iter().filter(|添字| !可視度.影可視度が変わったか(**添字)).count();
    if はみ出し != 0 {
        return Err(format!(
            "色が変わった{}画素のうち{はみ出し}画素で影可視度が動いていない。影の再配分では説明できない差である",
            色が変わった画素.len()
        ));
    }
    Ok(format!(
        "深度は全画素バイト一致し、色が変わった{}画素はすべて影可視度も変わった(影可視度が動いたのは{}画素)",
        色が変わった画素.len(),
        可視度.影可視度が変わった画素数()
    ))
}

/// 4つの採取がすべて後処理なしであり、色の対が診断でなく本番の色であることを確かめてから読む。
fn 色の対を読む(置き場: &Path) -> Result<(検収画像, 検収画像), String> {
    for (名前, 影可視度を可視化したか) in [
        ("shadow_reference", false),
        ("shadow_candidate", false),
        ("shadow_reference_visibility", true),
        ("shadow_candidate_visibility", true),
    ] {
        let 旗 = 採取の旗::由来ファイルから読む(置き場, 名前)?;
        if 旗.後処理を使うか() {
            return Err(format!("{名前}は後処理ありで採ってある。影の検査点は4つとも後処理なしで採る"));
        }
        let 記録 = 旗
            .影可視度を可視化したか()
            .ok_or_else(|| format!("{名前}の由来に影可視度の可視化の記録が無い。この名前を採り直す必要がある"))?;
        if 記録 != 影可視度を可視化したか {
            return Err(format!(
                "{名前}の影可視度の可視化が記録と食い違う(記録は{記録}、この名前が要るのは{影可視度を可視化したか})"
            ));
        }
    }
    let 対照 = 検収画像::読む(置き場, "shadow_reference")?;
    let 候補 = 検収画像::読む(置き場, "shadow_candidate")?;
    対照.同じ寸法を課す(&候補)?;
    Ok((対照, 候補))
}

/// 幾何画素が0件の絵どうしを突き合わせても何も検査していないため、幾何が写っていることも同時に課す。
fn 深度が全画素で一致することを課す(対照: &検収画像, 候補: &検収画像) -> Result<(), String> {
    let 深度差 = (0..対照.画素数()).filter(|添字| 対照.深度画素(*添字) != 候補.深度画素(*添字)).count();
    let 非有限 = 対照.非有限深度数() + 候補.非有限深度数();
    let 幾何画素数 = 対照.深度.iter().filter(|深度| **深度 > 0.0).count();
    if 深度差 != 0 || 非有限 != 0 || 幾何画素数 == 0 {
        return Err(format!("深度差={深度差} 非有限={非有限} 対照の幾何画素数={幾何画素数}"));
    }
    Ok(())
}
