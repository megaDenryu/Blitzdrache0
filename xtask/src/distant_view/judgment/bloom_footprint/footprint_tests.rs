//! にじみの足跡の上限の導出と、発生源からの距離の測り方の反証。

#![allow(clippy::unwrap_used)]

use super::{にじみの足跡, 段の寸法列, 画面距離の上限};

/// 固定構図の1280x720では段が5つ並ぶ。最下段の縦は45の半分の22.5でなく22であり、倍々にならない。
#[test]
fn 固定構図の段は五つで最下段の縦は倍々にならない() {
    assert_eq!(段の寸法列(1280, 720), vec![(640, 360), (320, 180), (160, 90), (80, 45), (40, 22)]);
}

/// 横は縮小2.5x(1+2+4+8+16)と拡大1.5x(32+16+8+4)と最後の標本1で168.5画素、縦は最下段のテクセルが33画素になるため
/// 169.5画素であり、大きい方を切り上げて170画素になる。この数が動いたらにじみの実装か画面の寸法が変わっている。
#[test]
fn 固定構図の足跡の上限は百七十画素である() {
    assert_eq!(画面距離の上限(1280, 720), 170);
}

/// 小さい画面では段が最小辺で打ち切られ、上限も縮む。上限を寸法から導いていることの反証である。
#[test]
fn 小さい画面では段が打ち切られて上限が縮む() {
    assert_eq!(段の寸法列(64, 64), vec![(32, 32), (16, 16)]);
    assert!(画面距離の上限(64, 64) < 画面距離の上限(1280, 720));
}

/// 斜めも1歩と数えるため、発生源の斜め隣は距離1になる。
#[test]
fn 発生源の斜め隣は距離一である() {
    let mut 発生源 = vec![false; 25];
    発生源[12] = true;
    let 足跡 = にじみの足跡::求める(5, 5, &発生源);
    assert_eq!(足跡.発生源からの距離(12), 0);
    assert_eq!(足跡.発生源からの距離(6), 1);
    assert_eq!(足跡.発生源からの距離(18), 1);
    assert_eq!(足跡.発生源からの距離(0), 2);
    assert_eq!(足跡.発生源からの距離(24), 2);
}

/// 発生源が1つも無ければどの画素も足跡の外になる。遠景が1画素も出ていない絵を黙って通さない。
#[test]
fn 発生源が無ければ全画素が足跡の外になる() {
    let 足跡 = にじみの足跡::求める(4, 4, &[false; 16]);
    assert!((0..16).all(|添字| 足跡.発生源からの距離(添字) > 足跡.上限()));
}
