//! にじみの足跡の上限の導出と、発生源からの距離の測り方の反証。

#![allow(clippy::unwrap_used)]

use super::{にじみの足跡, 段のテクセル幅一覧, 画面距離の上限};

/// 固定構図の1280x720では段が5つ並び、テクセルはフル解像度の2画素から32画素まで倍々になる。
#[test]
fn 固定構図の段は五つでテクセルは二画素から三十二画素まで並ぶ() {
    assert_eq!(段のテクセル幅一覧(1280, 720), vec![2, 4, 8, 16, 32]);
}

/// 縮小2.5x(1+2+4+8+16)=77.5画素、拡大1.5x(32+16+8+4)=90画素、最後の標本1画素で168.5画素。
/// 切り上げて169画素になる。この数が動いたらにじみの実装か画面の寸法が変わっている。
#[test]
fn 固定構図の足跡の上限は百六十九画素である() {
    assert_eq!(画面距離の上限(1280, 720), 169);
}

/// 小さい画面では段が最小辺で打ち切られ、上限も縮む。上限を寸法から導いていることの反証である。
#[test]
fn 小さい画面では段が打ち切られて上限が縮む() {
    assert_eq!(段のテクセル幅一覧(64, 64), vec![2, 4]);
    assert!(画面距離の上限(64, 64) < 画面距離の上限(1280, 720));
}

/// 斜めも1歩と数えるため、発生源の斜め隣は距離1になる。
#[test]
fn 発生源の斜め隣は距離一である() {
    let mut 発生源 = vec![false; 25];
    発生源[12] = true;
    let 足跡 = にじみの足跡::求める(5, 5, &発生源);
    assert_eq!(足跡.発生源からの距離(12), 0);
    assert_eq!(足跡.発生源からの距離(6), 1);
    assert_eq!(足跡.発生源からの距離(18), 1);
    assert_eq!(足跡.発生源からの距離(0), 2);
    assert_eq!(足跡.発生源からの距離(24), 2);
}

/// 発生源が1つも無ければどの画素も足跡の外になる。遠景が1画素も出ていない絵を黙って通さない。
#[test]
fn 発生源が無ければ全画素が足跡の外になる() {
    let 足跡 = にじみの足跡::求める(4, 4, &[false; 16]);
    assert!((0..16).all(|添字| 足跡.足跡の外か(添字)));
}
