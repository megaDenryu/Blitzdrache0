//! 散布の検査点の2段の比較。担当するのは「どの対へどの厳しさを課すか」だけであり、個々の条件は各工程が持つ。
//! 受け取るのは採取の置き場、返すのは2段の要約か最初に破れた条件である。
//!
//! 2段に分ける理由は遠景の検査点と同じである。散布が触っていない地面の色の不変は後処理込みでは原理的に課せない。
//! 光のにじみは画面内の演算子であり、地面の一部が岩へ置き換われば離れた画素も量子化1段ぶん動く。
//! そこで不変は後処理を組まない対で厳密に課し、出荷される構成へは滲みとして説明できる形に収まっていることを課す。
//!
//! 有界検査の向きの条件だけは遠景と違う。遠景は明るい空を暗い地形へ置き換えるため向きが暗化に決まっていたが、
//! 散布は地面より明るい岩も暗い木も置くため、期待する向きを発生源の平均輝度の動きから決める。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「第6段階」

use std::path::Path;

use super::bloom_footprint::にじみの足跡;
use super::color_difference::{色の動く向き, 許可域外の色差};
use super::image_pair::検収画像;
use super::scatter_class::散布の画素の区分;
use super::scatter_geometry::散布の幾何の実測;
use super::verdict_names::{後処理の有無の綴り, 採取の後処理の判定名};
use crate::distant_view::error::遠景構図の検収エラー;
use crate::distant_view::provenance::採取の旗;

pub(super) fn 判定する(置き場: &Path) -> Result<String, 遠景構図の検収エラー> {
    let 主判定 = 主判定を課す(置き場)?;
    let 有界検査 = 有界検査を課す(置き場)?;
    Ok(format!("主判定(後処理なし)は{主判定}、有界検査(後処理あり)は{有界検査}"))
}

/// 散布が触っていない地面の色の不変を課す段。滲みが混ざらないため、1画素も許さない。
fn 主判定を課す(置き場: &Path) -> Result<String, 遠景構図の検収エラー> {
    let (対照, 候補, 区分) = 対を読む(置き場, "scatter_reference_no_post", "scatter_candidate_no_post", false)?;
    let 幾何 = 散布の幾何の実測::測る(&対照, &候補, &区分).課す()?;
    let 色差 = 許可域外の色差::集める(&対照, &候補, &区分.許可域の外の一覧());
    let 足跡 = にじみの足跡::求める(対照.幅, 対照.高さ, 区分.散布が現れた一覧());
    println!("[distant-view] 散布の主判定の診断: {}", 色差.分布の綴り(&足跡));
    let 色 = 色差.一画素も無いことを課す(&区分.近傍の一覧())?;
    Ok(format!("{幾何}・{色}"))
}

/// 出荷される構成のまま課す段。差が残ること自体は認め、滲みとして説明できる形に収まっていることを見る。
fn 有界検査を課す(置き場: &Path) -> Result<String, 遠景構図の検収エラー> {
    let (対照, 候補, 区分) = 対を読む(置き場, "scatter_reference", "scatter_candidate", true)?;
    let 幾何 = 散布の幾何の実測::測る(&対照, &候補, &区分).課す()?;
    let 発生源 = 区分.散布が現れた一覧();
    let 足跡 = にじみの足跡::求める(対照.幅, 対照.高さ, 発生源);
    let 向き = 色の動く向き::合計の変化から決める(発生源の輝度の変化の合計(&対照, &候補, 発生源));
    let 色 = 許可域外の色差::集める(&対照, &候補, &区分.許可域の外の一覧()).有界であることを課す(&足跡, 向き)?;
    Ok(format!("{幾何}・発生源の向きは{}・{色}", 向き.綴り()))
}

/// 散布が現れた画素で、色の3成分の変化を全部足した値。滲みが撒く光の増減の向きはこの符号で決まる。
/// 透明度を数えないのは、にじみが運ぶのが光であって不透明度ではないためである。
fn 発生源の輝度の変化の合計(対照: &検収画像, 候補: &検収画像, 発生源: &[bool]) -> i64 {
    let mut 合計 = 0_i64;
    for (添字, 発生源か) in 発生源.iter().enumerate() {
        if !発生源か {
            continue;
        }
        for 成分 in 0..3 {
            合計 += i64::from(候補.色画素(添字)[成分]) - i64::from(対照.色画素(添字)[成分]);
        }
    }
    合計
}

/// 絵を読む前に採取の旗を照合する。段が要る構成と違う絵を突き合わせても、絵からはその食い違いが分からない。
fn 対を読む(
    置き場: &Path,
    対照名: &str,
    候補名: &str,
    後処理を使うか: bool,
) -> Result<(検収画像, 検収画像, 散布の画素の区分), 遠景構図の検収エラー> {
    for 名前 in [対照名, 候補名] {
        let 旗 = 採取の旗::由来ファイルから読む(置き場, 名前)?;
        採取の後処理の判定名(名前, "この検査点は後処理の有無で対を分けて課す")
            .綴りの一致を課す(後処理の有無の綴り(旗.後処理を使うか()), 後処理の有無の綴り(後処理を使うか))?;
    }
    let 対照 = 検収画像::読む(置き場, 対照名)?;
    let 候補 = 検収画像::読む(置き場, 候補名)?;
    対照.同じ寸法を課す(&候補)?;
    let 区分 = 散布の画素の区分::求める(&対照, &候補);
    Ok((対照, 候補, 区分))
}
