//! 散布の検査点の3段の比較。担当するのは「どの対へどの厳しさを課すか」だけであり、個々の条件は各工程が持つ。
//! 受け取るのは採取の置き場、返すのは3段の要約か最初に破れた条件である。対の読み取りは`pair`が持つ。
//!
//! **3段に分けるのは、絵を変える機構が3つ重なっているためである。** 地面へ物を置くと、(1)その物が画素を覆い、
//! (2)その物の影と遮蔽が周りの地面を暗くし、(3)光のにじみがその変化を画面の広い範囲へ運ぶ。
//! 遠景の検査点が2段で足りたのは、遠景が空を置き換えるだけで近傍へ影も遮蔽も落とさなかったためである。
//!
//! 2026-08-16に岩2種だけを散らしていた時点の実測がこの分け方の根拠である。影と遮蔽を入れたまま後処理だけを切った対では、散布が覆っていない地面が388画素動いた。
//! 全件が岩から12画素以内(10画素以内が383件)で明化を1件も含まず、接地影と遮蔽の指紋である。木を散らすようになった後の絵ではこの数は変わる。
//! 免除帯を12画素へ広げる案は採らない。第5段階が「足跡の広さは後処理の実装から導き、実測に合わせて決めない」と
//! 定めた規律に反するためである。代わりに機構ごとに構成を分け、各段が自分の機構だけを見る。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「第6段階」

mod pair;

use std::path::Path;

use pair::{対を読む, 期待する構成, 色が動いた画素の一覧};

use super::bloom_footprint::にじみの足跡;
use super::bloom_source::にじみへ光を出す画素の増減;
use super::color_difference::{色の動く向き, 許可域外の色差};
use super::scatter_geometry::散布の幾何の実測;
use crate::distant_view::error::遠景構図の検収エラー;

pub(super) fn 判定する(置き場: &Path) -> Result<String, 遠景構図の検収エラー> {
    let 主判定 = 主判定を課す(置き場)?;
    let 陰影 = 陰影の有界検査を課す(置き場)?;
    let にじみ = にじみの有界検査を課す(置き場)?;
    Ok(format!("主判定(素)は{主判定}、陰影の有界検査は{陰影}、にじみの有界検査は{にじみ}"))
}

/// 幾何だけが変わる構成で、散布が触っていない地面の色の不変を課す段。影も遮蔽もにじみも組まないため、
/// 免除帯は2画素のままで1画素も許さない。
fn 主判定を課す(置き場: &Path) -> Result<String, 遠景構図の検収エラー> {
    let (対照, 候補, 区分) = 対を読む(置き場, "scatter_reference_bare", "scatter_candidate_bare", 期待する構成::素)?;
    let 幾何 = 散布の幾何の実測::測る(&対照, &候補, &区分).課す()?;
    let 色 = 許可域外の色差::集める(&対照, &候補, &区分.許可域の外の一覧()).一画素も無いことを課す(&区分.近傍の一覧())?;
    Ok(format!("{幾何}・{色}"))
}

/// 影と遮蔽を入れ、にじみだけを切った段。差が残ること自体は認め、向きだけを課す。
///
/// **向きが暗化に決まるのは機構からである。** 不透明な物体を地面へ置くことは、その物体が覆っていない面へ届く光を
/// 減らすことしかできない。この描画器は物体からの反射光を面へ戻さないため、明るくなる道が無い。
/// 階調の大きさと発生源からの距離は診断として記録し、合否には使わない。上限を置くなら実測でなく
/// 遮蔽の半径と太陽高度から導く必要があり、その導出はこの段が守る性質(向き)に何も足さない。
fn 陰影の有界検査を課す(置き場: &Path) -> Result<String, 遠景構図の検収エラー> {
    let (対照, 候補, 区分) = 対を読む(置き場, "scatter_reference_no_post", "scatter_candidate_no_post", 期待する構成::にじみなし)?;
    let 幾何 = 散布の幾何の実測::測る(&対照, &候補, &区分).課す()?;
    let 色差 = 許可域外の色差::集める(&対照, &候補, &区分.許可域の外の一覧());
    let 足跡 = にじみの足跡::求める(対照.幅, 対照.高さ, 区分.散布が現れた一覧());
    println!("[distant-view] 陰影の有界検査の診断: {}", 色差.分布の綴り(&足跡));
    let 色 = 色差.向きだけを課す(色の動く向き::暗化)?;
    Ok(format!("{幾何}・{色}"))
}

/// 出荷される構成のまま課す段。陰影がすでに説明した画素を差し引き、にじみだけが動かした画素へ、にじみが
/// 運べる範囲に収まっていることを課す。発生源の変化が一方向のときは向きも課す。
///
/// にじみの発生源を「散布が現れた画素と、陰影の対で色が動いた画素の和」にするのは、にじみが読むのが
/// 後処理より前の絵だからである。その絵ではその2つの集合が動いており、にじみはそこから光を撒く。
///
/// **階調の大きさは課さない。** にじみが撒く光の減り方は場面の明るさに比例し、上限を機構から導く式が無い。
/// 遠景の段が使う2階調は遠景の免除帯の形が作った値であり、散布の免除帯へ持ち込むと機構でなく構図を課すことになる。
fn にじみの有界検査を課す(置き場: &Path) -> Result<String, 遠景構図の検収エラー> {
    let (陰影の対照, 陰影の候補, _) = 対を読む(置き場, "scatter_reference_no_post", "scatter_candidate_no_post", 期待する構成::にじみなし)?;
    let 陰影で動いた = 色が動いた画素の一覧(&陰影の対照, &陰影の候補);
    let (対照, 候補, 区分) = 対を読む(置き場, "scatter_reference", "scatter_candidate", 期待する構成::出荷)?;
    let 幾何 = 散布の幾何の実測::測る(&対照, &候補, &区分).課す()?;
    let 散布が現れた = 区分.散布が現れた一覧();
    let にじみだけの許可域の外: Vec<bool> = 区分
        .許可域の外の一覧()
        .iter()
        .enumerate()
        .map(|(添字, 外か)| *外か && !陰影で動いた[添字])
        .collect();
    let 発生源: Vec<bool> = (0..散布が現れた.len()).map(|添字| 散布が現れた[添字] || 陰影で動いた[添字]).collect();
    let 足跡 = にじみの足跡::求める(対照.幅, 対照.高さ, &発生源);
    let 増減 = にじみへ光を出す画素の増減::数える(&陰影の対照, &陰影の候補, &発生源);
    let 発生源の向き = 増減.向きを決める();
    let 色差 = 許可域外の色差::集める(&対照, &候補, &にじみだけの許可域の外);
    println!("[distant-view] にじみの有界検査の診断: {}・{}", 色差.分布の綴り(&足跡), 増減.診断の綴り());
    let 色 = 色差.足跡の内側であることを課す(&足跡, 発生源の向き)?;
    Ok(format!("{幾何}・発生源の変化は{}・{色}", 発生源の向き.綴り()))
}
