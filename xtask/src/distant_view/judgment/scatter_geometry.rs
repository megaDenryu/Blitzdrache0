//! 散布の検査点で深度だけから決まる不変条件を両方の対へ課す工程。受け取るのは対照と候補の検収画像と散布の区分、
//! 返すのは満たしたときの要約か、破れた条件を数で名指した判定の破れである。
//!
//! 課すのは、背景のマスクが動かないこと・深度が全画素で有限であること・先読みの縁に空隙が無いこと・
//! 幾何が遠ざかった画素が無いこと・散布が実際に絵へ現れていることの5つである。
//!
//! 幾何が遠ざかった画素を0にするのは、散布物が地面の手前にしか現れないためである。逆向き深度では手前ほど
//! 値が大きいから、候補の深度が対照より小さい画素は「そこにあった地面が消えたか歪んだ」ことを意味する。
//!
//! 後処理は深度画像へ触れないため、この契約は後処理ありの対でも同じ厳しさで通らなければならない。

use super::gap;
use super::image_pair::検収画像;
use super::scatter_class::散布の画素の区分;
use super::verdict_names::幾何契約の判定名;
use crate::acceptance::判定の破れ;

pub(super) struct 散布の幾何の実測 {
    背景マスク差: usize,
    非有限: usize,
    空隙: usize,
    遠ざかった: usize,
    散布が覆った: usize,
}

impl 散布の幾何の実測 {
    pub(super) fn 測る(対照: &検収画像, 候補: &検収画像, 区分: &散布の画素の区分) -> Self {
        let mut 実測 = Self {
            背景マスク差: 0,
            非有限: 対照.非有限深度数() + 候補.非有限深度数(),
            空隙: gap::閉じた先読み縁の空隙画素を数える(対照, 候補),
            遠ざかった: 0,
            散布が覆った: 0,
        };
        for 添字 in 0..区分.画素数() {
            if 区分.対照幾何か(添字) != 区分.候補幾何か(添字) {
                実測.背景マスク差 += 1;
            }
            if 区分.対照幾何か(添字) && 区分.候補幾何か(添字) && 候補.深度[添字] < 対照.深度[添字] {
                実測.遠ざかった += 1;
            }
            if 区分.散布が覆ったか(添字) {
                実測.散布が覆った += 1;
            }
        }
        実測
    }

    pub(super) fn 課す(&self) -> Result<String, 判定の破れ> {
        let 綴り = self.綴り();
        幾何契約の判定名("背景と幾何のマスクが食い違った画素", &綴り).零件であることを課す(self.背景マスク差)?;
        幾何契約の判定名("有限でない深度の画素", &綴り).零件であることを課す(self.非有限)?;
        幾何契約の判定名("閉じた先読みの縁の空隙の画素", &綴り).零件であることを課す(self.空隙)?;
        幾何契約の判定名("幾何が遠ざかった画素", &綴り).零件であることを課す(self.遠ざかった)?;
        if self.散布が覆った == 0 {
            return Err(幾何契約の判定名("散布が覆った画素", &綴り).あるはずのものが無い破れ());
        }
        Ok(format!("散布が覆った{}画素", self.散布が覆った))
    }

    fn 綴り(&self) -> String {
        format!(
            "背景マスク差={} 非有限={} 空隙={} 遠ざかった={} 散布が覆った={}",
            self.背景マスク差, self.非有限, self.空隙, self.遠ざかった, self.散布が覆った
        )
    }
}
