//! 散布の検査点で深度だけから決まる不変条件を両方の対へ課す工程。受け取るのは対照と候補の検収画像と散布の区分、
//! 返すのは満たしたときの要約か、破れた条件を数で名指した判定の破れである。
//!
//! 課すのは、幾何が消えた画素が無いこと・深度が全画素で有限であること・幾何が遠ざかった画素が無いこと・
//! 散布が実際に絵へ現れていることの4つである。
//!
//! **背景と幾何のマスクの変化は向きで分ける。** 背景から幾何への変化は、丘の上の個体が地平線より上へ出て
//! 空を背に立った正当な見え方である(2026-08-16の実測で153画素、親が絵を起こして確定した)。幾何から背景への
//! 変化だけが「そこにあった地面が消えた」ことを意味する。向きを見ずにマスクの食い違いを0件で課すと、正当な絵が落ちる。
//!
//! **幾何が遠ざかった画素を0にするのは、散布物が地面の手前にしか現れないためである。** 逆向き深度では手前ほど
//! 値が大きいから、両方に幾何があって候補の深度が対照より小さい画素は、地面が消えたか歪んだことを意味する。
//!
//! **先読みの縁の空隙は課さない。** あの工程は「対照で背景・候補で幾何」を遠景と読む分類であり、その読みが
//! 成り立つのは遠景を焼かない実行と焼く実行を比べる対だけである。散布の対では同じ条件が「散布が空を背に立った画素」を
//! 指すため、丘の上の個体が地平線の際に作る空の窪みを穴として数える(2026-08-16に2画素・1成分で実測した)。
//! 散布が地形へ穴を開けたなら、それは幾何が背景へ変わった画素として現れる。上の第1の条件がそれを課している。
//!
//! 後処理は深度画像へ触れないため、この契約は後処理ありの対でも同じ厳しさで通らなければならない。

use super::image_pair::検収画像;
use super::scatter_class::散布の画素の区分;
use super::verdict_names::幾何契約の判定名;
use crate::acceptance::判定の破れ;

pub(super) struct 散布の幾何の実測 {
    幾何が消えた: usize,
    空を背に立った: usize,
    非有限: usize,
    遠ざかった: usize,
    散布が現れた: usize,
}

impl 散布の幾何の実測 {
    pub(super) fn 測る(対照: &検収画像, 候補: &検収画像, 区分: &散布の画素の区分) -> Self {
        let mut 実測 = Self {
            幾何が消えた: 0,
            空を背に立った: 0,
            非有限: 対照.非有限深度数() + 候補.非有限深度数(),
            遠ざかった: 0,
            散布が現れた: 0,
        };
        for 添字 in 0..区分.画素数() {
            let (対照幾何, 候補幾何) = (区分.対照幾何か(添字), 区分.候補幾何か(添字));
            if 対照幾何 && !候補幾何 {
                実測.幾何が消えた += 1;
            }
            if !対照幾何 && 候補幾何 {
                実測.空を背に立った += 1;
            }
            if 対照幾何 && 候補幾何 && 候補.深度[添字] < 対照.深度[添字] {
                実測.遠ざかった += 1;
            }
            if 区分.散布が現れた一覧()[添字] {
                実測.散布が現れた += 1;
            }
        }
        実測
    }

    pub(super) fn 課す(&self) -> Result<String, 判定の破れ> {
        let 綴り = self.綴り();
        幾何契約の判定名("幾何が背景へ変わった画素", &綴り).零件であることを課す(self.幾何が消えた)?;
        幾何契約の判定名("有限でない深度の画素", &綴り).零件であることを課す(self.非有限)?;
        幾何契約の判定名("幾何が遠ざかった画素", &綴り).零件であることを課す(self.遠ざかった)?;
        if self.散布が現れた == 0 {
            return Err(幾何契約の判定名("散布が現れた画素", &綴り).あるはずのものが無い破れ());
        }
        Ok(format!(
            "散布が現れた{}画素(うち空を背に立ったもの{}画素)",
            self.散布が現れた, self.空を背に立った
        ))
    }

    fn 綴り(&self) -> String {
        format!(
            "幾何が消えた={} 空を背に立った={} 非有限={} 遠ざかった={} 散布が現れた={}",
            self.幾何が消えた, self.空を背に立った, self.非有限, self.遠ざかった, self.散布が現れた
        )
    }
}
