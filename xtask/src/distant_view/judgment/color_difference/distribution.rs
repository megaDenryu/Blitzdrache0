//! 許可域の外へ出た差の分布を診断の1行にする工程。受け取るのは差の一覧とにじみの足跡、返すのは1行の綴りである。
//!
//! 判定の合否には使わない。距離と向きを添えるのは、散布のように「物を置いたことが周りの陰影を変える」段で、
//! 差が発生源の近くに集まっているのか画面全体に散っているのか、暗化だけなのか明化を含むのかで
//! 原因の当たりが変わるためである。落ちた件数だけでは次の一手が決まらない。

use super::にじみの足跡;
use super::許可域外の色差;

impl 許可域外の色差 {
    /// 差の分布の1行。
    pub(in crate::distant_view::judgment) fn 分布の綴り(&self, 足跡: &にじみの足跡) -> String {
        let 最大階調差 = self.一覧.iter().map(|画素| 画素.最大階調差).max().unwrap_or(0);
        let 最大距離 = self.一覧.iter().map(|画素| 足跡.発生源からの距離(画素.添字)).max().unwrap_or(0);
        let 発生源から十画素以内 = self.一覧.iter().filter(|画素| 足跡.発生源からの距離(画素.添字) <= 10).count();
        let 明化を含む = self.一覧.iter().filter(|画素| 画素.明化を含むか).count();
        format!(
            "許可域の外の色差{}画素(最大{最大階調差}階調・発生源から最大{最大距離}画素・10画素以内が{発生源から十画素以内}件・明化を含むものが{明化を含む}件)",
            self.一覧.len()
        )
    }
}
