//! 色が動いてよい向きと、機構がその向きを決められるかどうか。受け取るのは変化した画素または発生源の増減、
//! 返すのはその画素が期待と逆へ動いたか、または課せる向きがあるかである。
//!
//! 2つの型を1つのファイルへ置くのは、どちらも「向き」という1つの関心事の別の側面であるためである。
//! `色の動く向き`は周りの画素へ課す向きを表し、`発生源の変化の向き`はその向きを機構が決められるかを表す。
//!
//! **向きを課せるのは発生源の変化が全域で同符号のときだけである。** にじみは非負の重みの線形作用素であり、
//! 発生源の変化が全部同じ符号なら周りの変化も同じ符号になる。増加と減少が混ざると、離れた画素がどちらへ
//! 動くかは「どちらの源が近いか」という幾何で決まり、機構は何も保証しない。合計の符号で1つ選ぶ決め方は
//! 採らない。2026-08-16の実測では、画素の数で数えるか光の量で数えるか、どの明るさで数えるかによって
//! 符号が反転した。遠景は明るい空を暗い地形へ置き換える一方向であるため、暗化を明示で渡す。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「第6段階」

/// 周りの画素へ課す、色が動いてよい向き。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(in crate::distant_view) enum 色の動く向き {
    暗化,
    明化,
}

impl 色の動く向き {
    pub(super) fn 逆へ動いたか(self, 明化を含むか: bool, 暗化を含むか: bool) -> bool {
        match self {
            Self::暗化 => 明化を含むか,
            Self::明化 => 暗化を含むか,
        }
    }

    pub(in crate::distant_view) fn 綴り(self) -> &'static str {
        match self {
            Self::暗化 => "暗化",
            Self::明化 => "明化",
        }
    }
}

/// 発生源の変化が周りの向きを決めるかどうか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(in crate::distant_view) enum 発生源の変化の向き {
    一方向(色の動く向き),
    増加と減少の混在,
}

impl 発生源の変化の向き {
    /// にじみへ光を出すようになった画素の数と、出さなくなった画素の数から決める。両方が0のときを暗化の
    /// 一方向とするのは、発生源が動かないなら周りも動かないはずであり、そのとき動いた画素はどちらの向きを
    /// 期待しても破れとして現れるためである。
    pub(in crate::distant_view) fn 増減の数から決める(増えた画素: usize, 減った画素: usize) -> Self {
        match (増えた画素 > 0, 減った画素 > 0) {
            (true, true) => Self::増加と減少の混在,
            (true, false) => Self::一方向(色の動く向き::明化),
            (false, true) | (false, false) => Self::一方向(色の動く向き::暗化),
        }
    }

    pub(in crate::distant_view) fn 綴り(self) -> String {
        match self {
            Self::一方向(向き) => format!("一方向の{}", 向き.綴り()),
            Self::増加と減少の混在 => "増加と減少の混在".to_string(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::{発生源の変化の向き, 色の動く向き};

    #[test]
    fn 暗化を期待する側は明化を含む画素だけを逆と見る() {
        let 向き = 色の動く向き::暗化;
        assert!(向き.逆へ動いたか(true, false), "明化だけの画素を逆と見なかった");
        assert!(!向き.逆へ動いたか(false, true), "暗化だけの画素を逆と見た");
        assert!(向き.逆へ動いたか(true, true), "明暗が混ざる画素を逆と見なかった");
    }

    #[test]
    fn 明化を期待する側は暗化を含む画素だけを逆と見る() {
        let 向き = 色の動く向き::明化;
        assert!(!向き.逆へ動いたか(true, false), "明化だけの画素を逆と見た");
        assert!(向き.逆へ動いたか(false, true), "暗化だけの画素を逆と見なかった");
        assert!(向き.逆へ動いたか(true, true), "明暗が混ざる画素を逆と見なかった");
    }

    #[test]
    fn 増減が両方あるときだけ混在になる() {
        assert_eq!(発生源の変化の向き::増減の数から決める(1, 1), 発生源の変化の向き::増加と減少の混在);
        assert_eq!(
            発生源の変化の向き::増減の数から決める(1, 0),
            発生源の変化の向き::一方向(色の動く向き::明化)
        );
        assert_eq!(
            発生源の変化の向き::増減の数から決める(0, 1),
            発生源の変化の向き::一方向(色の動く向き::暗化)
        );
        assert_eq!(
            発生源の変化の向き::増減の数から決める(0, 0),
            発生源の変化の向き::一方向(色の動く向き::暗化)
        );
    }
}
