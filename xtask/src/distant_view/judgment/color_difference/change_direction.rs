//! 色が動いてよい向き。受け取るのは変化した画素、返すのはその画素が期待と逆へ動いたかである。
//!
//! 向きを型で持つのは、有界検査が「発生源の変化と同じ向きにしか周りが動かないこと」を課すためである。
//! 遠景の検査点では発生源が明るい空を暗い地形へ置き換えるため向きは暗化に決まっていたが、散布の検査点では
//! 地面より明るい岩と暗い木の両方を置くため、向きは発生源の平均輝度の動きから決まる。
//! 向きの条件を丸ごと外すと、滲みでは説明できない変化を見分ける網を1つ失う。

/// 発生源が色を動かした向き。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(in crate::distant_view) enum 色の動く向き {
    暗化,
    明化,
}

impl 色の動く向き {
    /// 発生源の画素で足し合わせた輝度の変化の符号から向きを決める。平均でなく合計で決めるのは、
    /// 向きが符号だけで決まり、件数で割っても符号が変わらないためである。実数への変換を通さないぶん、
    /// 数値のasキャストも丸めも入らない。0のときは暗化とする。発生源が輝度を1つも動かさないなら
    /// 周りも動かないはずであり、そのとき逆へ動いた画素はどちらの向きを期待しても破れとして現れる。
    pub(in crate::distant_view) fn 合計の変化から決める(合計の変化: i64) -> Self {
        if 合計の変化 > 0 { Self::明化 } else { Self::暗化 }
    }

    pub(super) fn 逆へ動いたか(self, 明化を含むか: bool, 暗化を含むか: bool) -> bool {
        match self {
            Self::暗化 => 明化を含むか,
            Self::明化 => 暗化を含むか,
        }
    }

    pub(in crate::distant_view) fn 綴り(self) -> &'static str {
        match self {
            Self::暗化 => "暗化",
            Self::明化 => "明化",
        }
    }
}

#[cfg(test)]
mod tests {
    use super::色の動く向き;

    #[test]
    fn 合計が正なら明化で負と零なら暗化である() {
        assert_eq!(色の動く向き::合計の変化から決める(1), 色の動く向き::明化);
        assert_eq!(色の動く向き::合計の変化から決める(-1), 色の動く向き::暗化);
        assert_eq!(色の動く向き::合計の変化から決める(0), 色の動く向き::暗化);
    }

    #[test]
    fn 暗化を期待する側は明化を含む画素だけを逆と見る() {
        let 向き = 色の動く向き::暗化;
        assert!(向き.逆へ動いたか(true, false), "明化だけの画素を逆と見なかった");
        assert!(!向き.逆へ動いたか(false, true), "暗化だけの画素を逆と見た");
        assert!(向き.逆へ動いたか(true, true), "明暗が混ざる画素を逆と見なかった");
    }

    #[test]
    fn 明化を期待する側は暗化を含む画素だけを逆と見る() {
        let 向き = 色の動く向き::明化;
        assert!(!向き.逆へ動いたか(true, false), "明化だけの画素を逆と見た");
        assert!(向き.逆へ動いたか(false, true), "暗化だけの画素を逆と見なかった");
        assert!(向き.逆へ動いたか(true, true), "明暗が混ざる画素を逆と見なかった");
    }
}
