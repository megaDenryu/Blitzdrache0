//! 1画素の色の変化を測って大きさと向きにする工程。受け取るのは対照と候補の検収画像と画素の添字、
//! 返すのは変化があったときだけその画素の記録である。
//!
//! 大きさをチャンネルごとの差の絶対値の最大で採るのは、有界検査が「量子化が何段ずれたか」を見るためである。
//! 向きを両側の有無で持つのは、有界検査が「発生源と同じ向きにしか周りが動かないこと」を課すためである。
//! 滲みが撒く光の増減はチャンネルをまたいで同じ向きへ効くため、1チャンネルでも逆へ動いたならそれは別の原因である。
//! 透明度も同じ規則で数える。変化しないはずの成分が動いたなら、それも滲みでは説明できない。

use super::super::image_pair::検収画像;

pub(super) struct 変化した画素 {
    pub(super) 添字: usize,
    pub(super) 最大階調差: u16,
    pub(super) 明化を含むか: bool,
    pub(super) 暗化を含むか: bool,
}

impl 変化した画素 {
    pub(super) fn 求める(対照: &検収画像, 候補: &検収画像, 添字: usize) -> Option<Self> {
        let 差一覧: Vec<i16> = 対照
            .色画素(添字)
            .iter()
            .zip(候補.色画素(添字))
            .map(|(元, 先)| i16::from(*先) - i16::from(*元))
            .collect();
        let 最大階調差 = 差一覧.iter().map(|差| 差.unsigned_abs()).max().unwrap_or(0);
        (最大階調差 != 0).then(|| Self {
            添字,
            最大階調差,
            明化を含むか: 差一覧.iter().any(|差| *差 > 0),
            暗化を含むか: 差一覧.iter().any(|差| *差 < 0),
        })
    }
}
