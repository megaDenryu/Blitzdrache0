//! 遠景の検査点の有界検査だけが課す階調の上限と、その段の要約の組み立て。受け取るのは差の一覧と
//! にじみの足跡と期待する向き、返すのは満たしたときの要約か、破れた条件を名指した判定の破れである。
//!
//! 散布の3段と分けて持つのは、階調の大きさへ上限を課すのが遠景の段だけであり、その上限の根拠が
//! 遠景の対の構図に固有だからである。触れるのは差の一覧だけであり、集める規則には触れない。
//!
//! **上限を機構から導く式は無い。** にじみが撒く光の減り方は場面の明るさに比例する。ここは
//! 「量子化が1段ずれた程度の滲み」と「陰影そのものの退行」を分ける仕掛け線であり、工程Dの帰属診断で
//! 実測した分布(1階調22,720画素・2階調139画素・3階調以上0画素)の最大値をそのまま境界に置いている。
//!
//! **この上限を他の検査点へ広げてはならない。** 遠景の免除帯は対照の幾何の輪郭を2画素広げた帯であり、
//! 遠景の発生源は幾何の輪郭そのものであるから、発生源に最も近く振幅が最大になる輪の半分が構造的に免除される。
//! 散布の免除帯は散布の画素を2画素広げた帯であるため同じ輪が1画素も免除されず、同じにじみの機構でも
//! 3階調が現れる。2という値はにじみの性質ではなく、遠景の免除帯の形が作ったものである。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「第6段階」

use super::verdict_names::最大の階調差の判定名;
use super::{にじみの足跡, 色の動く向き, 許可域外の色差};
use crate::acceptance::判定の破れ;

/// 遠景の有界検査が許す1画素あたりの最大の階調差。3階調以上が出たらそれは滲みの範囲を超えた変化であり、
/// 緩めるのでなく原因を先に突き止める。
const 許す階調差: u16 = 2;

impl 許可域外の色差 {
    /// 遠景の有界検査。差が残ること自体は認めるが、滲みとして説明できる形に収まっていることを課す。
    ///
    /// 最も大きい差だけへ上限を課すのは、それが上限を守るなら残り全部も守るためである。1件ずつ課すと、
    /// 破れの文面が「たまたま最初に見つかった画素」を名指すことになる。
    pub(in crate::distant_view::judgment) fn 有界であることを課す(
        &self,
        足跡: &にじみの足跡,
        期待する向き: 色の動く向き,
    ) -> Result<String, 判定の破れ> {
        if let Some(画素) = self.一覧.iter().max_by_key(|画素| 画素.最大階調差) {
            最大の階調差の判定名(self.位置(画素)).上限を課す(画素.最大階調差, 許す階調差)?;
        }
        self.逆へ動いた画素が無いことを課す(期待する向き)?;
        self.発生源からの距離の上限を課す(足跡)?;
        Ok(format!(
            "許可域外の色差{}画素が全て{許す階調差}階調以内の{}であり、発生源から{}画素以内に収まった",
            self.一覧.len(),
            期待する向き.綴り(),
            足跡.上限()
        ))
    }
}
