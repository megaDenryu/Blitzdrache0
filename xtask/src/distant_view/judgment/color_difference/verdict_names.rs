//! 許可域外の色差が破れたときの文面の組み立て。受け取るのは破れた対象と同時に読ませたい実測、
//! 返すのは判定の名前である。
//!
//! 主判定の名前が近傍差と最初の画素と最大の階調差を丸ごと抱えるのは、件数だけでは次の一手が決まらないためである。
//! 近傍差が0なら免除帯の外の背景が動いており、0でなければ近傍チャンクの陰影そのものが動いている。

use crate::acceptance::判定の名前;

use super::super::pixel_location::画素の位置;

pub(super) fn 許可域外の色差の判定名(近傍差: usize, 最初の位置の綴り: &str, 最大階調差: u16) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "許可域の外で色が動いた画素(うち近傍チャンクの幾何画素は{近傍差}画素、最初の画素は{最初の位置の綴り}、最大の階調差は{最大階調差}階調である)"
    ))
}

pub(super) fn 最大の階調差の判定名(位置: 画素の位置) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("許可域の外で最も大きく色が動いた{位置}の階調差"))
}

pub(super) fn 逆へ動いた画素の判定名(期待する向きの綴り: &str, 最初の位置の綴り: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "許可域の外で発生源と逆へ動いた画素(最初の画素は{最初の位置の綴り}である。滲みで説明できるのは発生源と同じ{期待する向きの綴り}の側だけである)"
    ))
}

pub(super) fn 発生源からの距離の判定名(位置: 画素の位置) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("許可域の外で色が動いた画素のうち発生源から最も遠い{位置}の距離"))
}
