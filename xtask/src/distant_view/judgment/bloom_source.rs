//! 散布でにじみへ光を出す画素が増えたか減ったかを数える工程。受け取るのはにじみなしの対の2枚と
//! 発生源の画素集合、返すのは増減の数と、そこから決まる発生源の変化の向きである。
//!
//! にじみへ光を出すのは、明るさがソフト閾値の入り口を超えた画素だけである。散布はこの入り口を両方向へ跨ぐ。
//! 地平では明るい空を岩が隠して光を出す画素を減らし、近景では地面より明るい岩が入り口を超えて増やす。
//! 2026-08-16の実測は増えたもの409画素・減ったもの88画素であり、どちらも散布が現れた画素であった。
//! 出荷の絵の色差を発生源で足す決め方では、入り口を超えない明るい岩まで符号に参加するため向きが決まらない。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「第6段階」
//!
//! 注意: 2つの定数は`shaders/bloom_filters.slang`の`softThreshold`の写しであり、`cargo xtask conform`の
//! 定数の組が一致を見る。入り口を引き算で導くのは、値の写しだけを持って式の写しを持たないためである。

use super::color_difference::発生源の変化の向き;
use super::image_pair::検収画像;

/// にじみが光を全部通す明るさ。これを超えた分はそのままにじみへ入る。
const にじみが光を全部通す明るさ: f32 = 1.0;
/// にじみの入り口をなだらかにする幅。この幅だけ手前から光が少しずつ入り始める。
const にじみの入り口をなだらかにする幅: f32 = 0.5;

pub(super) struct にじみへ光を出す画素の増減 {
    増えた: usize,
    減った: usize,
}

impl にじみへ光を出す画素の増減 {
    pub(super) fn 数える(対照: &検収画像, 候補: &検収画像, 発生源: &[bool]) -> Self {
        let mut 増減 = Self { 増えた: 0, 減った: 0 };
        for (添字, 発生源か) in 発生源.iter().enumerate() {
            if !発生源か {
                continue;
            }
            match (光を出すか(対照.色画素(添字)), 光を出すか(候補.色画素(添字))) {
                (false, true) => 増減.増えた += 1,
                (true, false) => 増減.減った += 1,
                (false, false) | (true, true) => {}
            }
        }
        増減
    }

    pub(super) fn 向きを決める(&self) -> 発生源の変化の向き {
        発生源の変化の向き::増減の数から決める(self.増えた, self.減った)
    }

    pub(super) fn 診断の綴り(&self) -> String {
        format!(
            "にじみへ光を出すようになった発生源が{}画素・出さなくなった発生源が{}画素",
            self.増えた, self.減った
        )
    }
}

/// にじみへ光を出す画素か。にじみなしの絵は明るさを1で切り詰めて符号化したものであるが、入り口は
/// 切り詰めの位置より下にあるため、この判定はその絵の上でそのまま成り立つ。
fn 光を出すか(画素: &[u8]) -> bool {
    let 明るさ = 画素.iter().take(3).map(|成分| 線形の明るさへ戻す(*成分)).fold(0.0_f32, f32::max);
    明るさ > にじみが光を全部通す明るさ - にじみの入り口をなだらかにする幅
}

/// sRGBの符号値を線形の明るさへ戻す。スワップチェーンがSRGB形式であり、後処理を組まない実行の書き込みは
/// この符号化そのものになる。
/// 参照: `crates/blitz_app/src/reports/sky_pixel/srgb_encode.rs`
fn 線形の明るさへ戻す(符号値: u8) -> f32 {
    let 正規化 = f32::from(符号値) / 255.0;
    if 正規化 <= 0.040_45 {
        正規化 / 12.92
    } else {
        ((正規化 + 0.055) / 1.055).powf(2.4)
    }
}
