//! 影の検査点が読む4つの採取の照合と読み込み、および深度の一致の判定。
//! 受け取るのは採取の置き場、返すのは色の対か、器の破れか破れた判定である。
//!
//! 絵を読む前に4つの由来の旗をすべて照合する。段が要る構成と違う絵を突き合わせても、絵からはその食い違いが
//! 分からない。とりわけ再配分を切った側と切らない側の取り違えは、A/Bが同じ条件どうしの比較になり、
//! 差が出ないことをもって合格と読んでしまう。
//!
//! 欄そのものが無い由来は器の破れ(採り直しで直る)、欄はあるが値が食い違う由来は判定の破れとして返す。

use std::path::Path;

use super::super::image_pair::検収画像;
use super::super::verdict_names::{後処理の有無の綴り, 採取の後処理の判定名};
use super::verdict_names::{影の幾何の判定名, 採取の欄の判定名, 旗の綴り};
use crate::acceptance::判定の破れ;
use crate::distant_view::error::{採取の読み取りの破れ, 遠景構図の検収エラー};
use crate::distant_view::provenance::採取の旗;

/// 4つの採取の名前と、その名前が要る条件(影可視度を可視化するか・再配分を切るか)。
const 採取の一覧: [(&str, bool, bool); 4] = [
    ("shadow_reference", false, true),
    ("shadow_candidate", false, false),
    ("shadow_reference_visibility", true, true),
    ("shadow_candidate_visibility", true, false),
];

const 影可視度の可視化の欄: &str = "影可視度の可視化";
const 距離区分の再配分の欄: &str = "距離区分の再配分を切ったか";

pub(super) fn 色の対を読む(置き場: &Path) -> Result<(検収画像, 検収画像), 遠景構図の検収エラー> {
    for (名前, 影可視度を可視化したか, 明示境界を切ったか) in 採取の一覧 {
        let 旗 = 採取の旗::由来ファイルから読む(置き場, 名前)?;
        採取の後処理の判定名(名前, "影の検査点は4つとも後処理なしで採る")
            .綴りの一致を課す(後処理の有無の綴り(旗.後処理を使うか()), 後処理の有無の綴り(false))?;
        記録を照合する(名前, 影可視度の可視化の欄, 旗.影可視度を可視化したか(), 影可視度を可視化したか)?;
        記録を照合する(名前, 距離区分の再配分の欄, 旗.明示境界を切ったか(), 明示境界を切ったか)?;
    }
    let 対照 = 検収画像::読む(置き場, "shadow_reference")?;
    let 候補 = 検収画像::読む(置き場, "shadow_candidate")?;
    対照.同じ寸法を課す(&候補)?;
    Ok((対照, 候補))
}

/// 幾何画素が0件の絵どうしを突き合わせても何も検査していないため、幾何が写っていることも同時に課す。
pub(super) fn 深度が全画素で一致することを課す(対照: &検収画像, 候補: &検収画像) -> Result<(), 判定の破れ> {
    let 深度差 = (0..対照.画素数()).filter(|添字| 対照.深度画素(*添字) != 候補.深度画素(*添字)).count();
    let 非有限 = 対照.非有限深度数() + 候補.非有限深度数();
    let 幾何画素数 = 対照.深度.iter().filter(|深度| **深度 > 0.0).count();
    let 綴り = format!("深度差={深度差} 非有限={非有限} 対照の幾何画素数={幾何画素数}");
    影の幾何の判定名("深度が動いた画素", &綴り).零件であることを課す(深度差)?;
    影の幾何の判定名("有限でない深度の画素", &綴り).零件であることを課す(非有限)?;
    if 幾何画素数 == 0 {
        return Err(影の幾何の判定名("対照に幾何が写っている画素", &綴り).あるはずのものが無い破れ());
    }
    Ok(())
}

/// 欄が無い由来は、その欄を足す前に採ったものである。影の検査点はどの欄も要るため、記録なしを失敗にする。
fn 記録を照合する(名前: &str, 欄: &'static str, 記録: Option<bool>, 要る値: bool) -> Result<(), 遠景構図の検収エラー> {
    let Some(記録) = 記録 else {
        return Err(採取の読み取りの破れ::由来に欄の記録が無い {
            名前: 名前.to_string(), 欄
        }
        .into());
    };
    採取の欄の判定名(名前, 欄).綴りの一致を課す(旗の綴り(記録), 旗の綴り(要る値))?;
    Ok(())
}
