//! 影の検査点が破れたときの文面の組み立て。受け取るのは破れた対象と同時に読ませたい実測、返すのは判定の名前である。
//!
//! 旗の値をonとoffで述べるのは、由来ファイルがその2語で記録しているためである。破れを読んだ人が
//! 同じ綴りで由来ファイルを探せる。

use crate::acceptance::判定の名前;

use super::super::pixel_location::画素の位置;

pub(super) fn 採取の欄の判定名(採取の名前: &str, 欄: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{採取の名前}の由来が記録した{欄}"))
}

pub(super) fn 影の幾何の判定名(測るもの: &str, 幾何の実測の綴り: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{測るもの}(幾何の実測は{幾何の実測の綴り}である)"))
}

pub(super) fn 色が動いた向きの判定名(位置: 画素の位置, 可視度の向きの綴り: &str, 最大階調差: u16) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{位置}の色が動いた向き(影可視度の記録が{可視度の向きの綴り}ため色も同じ向きへ動くはずである。最大{最大階調差}階調動いた)"
    ))
}

pub(super) fn 記録の動きを伴わない色差の判定名(最初の画素の綴り: &str, 帰属を求める階調差: u16) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "影可視度の記録が動いていないのに{帰属を求める階調差}階調以上動いた画素(最初の画素は{最初の画素の綴り}。影の再配分では説明できない差である)"
    ))
}

/// 由来ファイルが旗を記録する2語。読み手が同じ綴りでファイルを探せるよう、記録の綴りをそのまま出す。
pub(super) fn 旗の綴り(立っているか: bool) -> &'static str {
    if 立っているか { "on" } else { "off" }
}
