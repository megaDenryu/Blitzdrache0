//! 1画素の色がどれだけ・どちらへ動いたかを測り、影可視度の向きと突き合わせる工程。
//! 受け取るのは対照と候補の検収画像と画素の添字、返すのは動きがあったときだけその記録である。
//!
//! 向きをチャンネルごとに見るのは、影の濃さの変化が全チャンネルを同じ向きへ動かすためである。直接光の色を
//! 掛けた量が増減するだけであり、あるチャンネルだけが逆へ動くことはない。輝度の平均で見ると、逆へ動いた
//! チャンネルが他のチャンネルに打ち消されて見えなくなる。透明度も同じ規則で数える。動かないはずの成分が
//! 動いたなら、それも影の再配分では説明できない。

use super::super::image_pair::検収画像;
use super::super::pixel_location::画素の位置;
use super::verdict_names::色が動いた向きの判定名;
use crate::acceptance::判定の破れ;

pub(super) struct 色の動き {
    最大階調差: u16,
    明るくなったチャンネルがあるか: bool,
    暗くなったチャンネルがあるか: bool,
}

impl 色の動き {
    pub(super) fn 求める(対照: &検収画像, 候補: &検収画像, 添字: usize) -> Option<Self> {
        let 差一覧: Vec<i16> = 対照
            .色画素(添字)
            .iter()
            .zip(候補.色画素(添字))
            .map(|(元, 先)| i16::from(*先) - i16::from(*元))
            .collect();
        let 最大階調差 = 差一覧.iter().map(|差| 差.unsigned_abs()).max().unwrap_or(0);
        (最大階調差 != 0).then(|| Self {
            最大階調差,
            明るくなったチャンネルがあるか: 差一覧.iter().any(|差| *差 > 0),
            暗くなったチャンネルがあるか: 差一覧.iter().any(|差| *差 < 0),
        })
    }

    pub(super) fn 最大階調差(&self) -> u16 {
        self.最大階調差
    }

    /// 影可視度が上がった画素は明るくなる側だけへ、下がった画素は暗くなる側だけへ動いていなければならない。
    /// 1つの画素の中で明暗が混ざることも認めない。影の濃さの変化は全チャンネルを同じ向きへ動かすためである。
    ///
    /// 綴りが一致する画素をここで返してしまうのは、判定の名前の組み立てが画素ごとの文字列の確保になるためである。
    /// 動いた画素は数十万に及ぶため、破れる画素だけが名前を作る。
    pub(super) fn 可視度と同じ向きであることを課す(
        &self,
        可視度が明るくなる向きか: bool,
        位置: 画素の位置,
    ) -> Result<(), 判定の破れ> {
        let 色の向き = self.動いた向きの綴り();
        let 可視度が求める向き = 明暗の綴り(可視度が明るくなる向きか);
        if 色の向き == 可視度が求める向き {
            return Ok(());
        }
        色が動いた向きの判定名(位置, 可視度の動きの綴り(可視度が明るくなる向きか), self.最大階調差)
            .綴りの一致を課す(色の向き, 可視度が求める向き)
    }

    fn 動いた向きの綴り(&self) -> &'static str {
        match (self.明るくなったチャンネルがあるか, self.暗くなったチャンネルがあるか) {
            (true, true) => "1つの画素の中で明暗が混ざった",
            (true, false) => 明暗の綴り(true),
            (false, true) => 明暗の綴り(false),
            (false, false) => "動いていない",
        }
    }
}

fn 明暗の綴り(明るくなるか: bool) -> &'static str {
    if 明るくなるか { "明るくなった" } else { "暗くなった" }
}

fn 可視度の動きの綴り(上がったか: bool) -> &'static str {
    if 上がったか { "上がった" } else { "下がった" }
}
