//! 色が動いた画素を1つずつ受け取り、影可視度の記録へ帰属できたかを数え上げる型。
//! 受け取るのは1画素ぶんの色の動きと記録の動き、返すのは向きの判定の結果と、走査を終えた後の帰属の判定である。
//!
//! 数を型が所有するのは、走査の途中の可変の状態を自由関数の連鎖へ参照で通さないためである。
//! 未帰属の件数を最後にまとめて課すのは、破れの文面が「最初の1画素」だけでなく総数も名指すためである。

use super::super::pixel_location::画素の位置;
use super::color_shift::色の動き;
use super::verdict_names::記録の動きを伴わない色差の判定名;
use super::帰属を求める階調差;
use crate::acceptance::判定の破れ;

pub(super) struct 色差の帰属の集計 {
    記録の動きを伴わない一階調: usize,
    未帰属の件数: usize,
    最初の未帰属: Option<(画素の位置, u16)>,
}

impl 色差の帰属の集計 {
    pub(super) fn 新しく始める() -> Self {
        Self {
            記録の動きを伴わない一階調: 0,
            未帰属の件数: 0,
            最初の未帰属: None,
        }
    }

    /// 記録が動いた画素には向きを課し、動いていない画素は帰属を求める階調差に届くかで振り分ける。
    pub(super) fn 一画素を見る(
        &mut self,
        動き: &色の動き,
        明るくなる向きへ動いたか: Option<bool>,
        位置: 画素の位置,
    ) -> Result<(), 判定の破れ> {
        match 明るくなる向きへ動いたか {
            Some(明るくなる向き) => 動き.可視度と同じ向きであることを課す(明るくなる向き, 位置),
            None if 動き.最大階調差() >= 帰属を求める階調差 => {
                self.未帰属の件数 += 1;
                self.最初の未帰属.get_or_insert((位置, 動き.最大階調差()));
                Ok(())
            }
            None => {
                self.記録の動きを伴わない一階調 += 1;
                Ok(())
            }
        }
    }

    pub(super) fn 記録の動きを伴わない色差が説明できることを課す(&self) -> Result<(), 判定の破れ> {
        let 最初の綴り = self
            .最初の未帰属
            .map_or_else(|| "無し".to_string(), |(位置, 階調差)| format!("{位置}が{階調差}階調動いた"));
        記録の動きを伴わない色差の判定名(&最初の綴り, 帰属を求める階調差).零件であることを課す(self.未帰属の件数)
    }

    pub(super) fn 記録の動きを伴わない色差の画素数(&self) -> usize {
        self.記録の動きを伴わない一階調
    }
}
