//! 散布の検査点が読む1つの対と、段ごとに要る採取の構成。受け取るのは置き場と2つの名前と構成、
//! 返すのは対照と候補の検収画像と散布の区分である。
//!
//! 絵を読む前に採取の旗を照合するのは、段が要る構成と違う絵を突き合わせても絵からはその食い違いが分からないためである。
//! 散布の検査点は3つの構成を使い分けるため、後処理の有無だけでは素の対と陰影の対を見分けられない。
//! 影のキャスターと局所可視性の欄も同じ厳しさで照合する。

use std::path::Path;

use super::super::image_pair::検収画像;
use super::super::scatter_class::散布の画素の区分;
use super::super::verdict_names::{後処理の有無の綴り, 採取の後処理の判定名};
use crate::distant_view::error::遠景構図の検収エラー;
use crate::distant_view::provenance::採取の旗;

/// 段ごとに要る採取の構成。3つの機構のうちどれを組んだ絵かを表す。
#[derive(Clone, Copy)]
pub(super) enum 期待する構成 {
    /// 影も遮蔽もにじみも組まない。幾何だけが変わる。
    素,
    /// 影と遮蔽は組み、にじみだけを切る。
    にじみなし,
    /// 出荷される構成。3つとも組む。
    出荷,
}

impl 期待する構成 {
    fn 後処理を使うか(self) -> bool {
        matches!(self, Self::出荷)
    }

    fn 局所可視性を使うか(self) -> bool {
        !matches!(self, Self::素)
    }

    fn 影のキャスターを切ったか(self) -> bool {
        matches!(self, Self::素)
    }

    fn 呼び名(self) -> &'static str {
        match self {
            Self::素 => "素(影も遮蔽もにじみも組まない)",
            Self::にじみなし => "にじみなし(影と遮蔽は組む)",
            Self::出荷 => "出荷(3つとも組む)",
        }
    }
}

/// 2枚の絵で色のバイト列が動いた画素。にじみの有界検査が「陰影がすでに説明した画素」を差し引くのに使う。
pub(super) fn 色が動いた画素の一覧(対照: &検収画像, 候補: &検収画像) -> Vec<bool> {
    (0..対照.画素数()).map(|添字| 対照.色画素(添字) != 候補.色画素(添字)).collect()
}

pub(super) fn 対を読む(
    置き場: &Path,
    対照名: &str,
    候補名: &str,
    構成: 期待する構成,
) -> Result<(検収画像, 検収画像, 散布の画素の区分), 遠景構図の検収エラー> {
    for 名前 in [対照名, 候補名] {
        旗を照合する(置き場, 名前, 構成)?;
    }
    let 対照 = 検収画像::読む(置き場, 対照名)?;
    let 候補 = 検収画像::読む(置き場, 候補名)?;
    対照.同じ寸法を課す(&候補)?;
    let 区分 = 散布の画素の区分::求める(&対照, &候補);
    Ok((対照, 候補, 区分))
}

fn 旗を照合する(置き場: &Path, 名前: &str, 構成: 期待する構成) -> Result<(), 遠景構図の検収エラー> {
    let 旗 = 採取の旗::由来ファイルから読む(置き場, 名前)?;
    let 説明 = 構成.呼び名();
    採取の後処理の判定名(名前, 説明).綴りの一致を課す(後処理の有無の綴り(旗.後処理を使うか()), 後処理の有無の綴り(構成.後処理を使うか()))?;
    採取の後処理の判定名(名前, 説明)
        .綴りの一致を課す(遮蔽の有無の綴り(旗.局所可視性を使うか()), 遮蔽の有無の綴り(構成.局所可視性を使うか()))?;
    採取の後処理の判定名(名前, 説明).綴りの一致を課す(
        影のキャスターの綴り(旗.影のキャスターを切ったか()),
        影のキャスターの綴り(Some(構成.影のキャスターを切ったか())),
    )?;
    Ok(())
}

fn 遮蔽の有無の綴り(使うか: bool) -> &'static str {
    if 使うか { "遮蔽あり" } else { "遮蔽なし" }
}

/// 欄を持たない古い採取は記録なしとして綴りを分ける。期待する側は必ず記録を持つため、
/// 古い採取を突き合わせると一致しない綴りとして落ち、採り直しを促せる。
fn 影のキャスターの綴り(切ったか: Option<bool>) -> &'static str {
    match 切ったか {
        Some(true) => "影のキャスターなし",
        Some(false) => "影のキャスターあり",
        None => "影のキャスターの記録なし",
    }
}
