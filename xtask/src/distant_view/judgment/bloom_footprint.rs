//! 光のにじみが1画素の変化を画面上どこまで運ぶかの上限と、変化の発生源から各画素までの画面距離。
//! 受け取るのは画面の寸法と発生源の画素集合、返すのは上限を知っていて距離を答える足跡である。
//!
//! 後処理ありの対で近傍の色が動くのは、遠景が地平の帯で明るい空を暗い地形へ置き換え、にじみが撒く光が
//! 減るためである。にじみは画面内の演算子であり台が遠景の輪郭より広いため、近傍不変は後処理込みでは
//! 原理的に達成できない。そこで「変化が発生源のにじみの足跡の内側に収まること」を代わりに課す。
//! 参照: `crates/blitz_app/src/reports/sky_pixel.rs`(にじみと明るさの圧縮が1画素の期待値を決めなくする既知の機構)
//!
//! 上限は3つの積み上げである。縮小は13タップが読み元の±2テクセルへ届き、バイリニアの標本がさらに
//! ±0.5テクセル広げるため1段あたり±2.5テクセル。拡大は3x3テントの±1テクセルとバイリニアの±0.5テクセルで
//! 1段あたり±1.5テクセル。最後に明るさの圧縮が拡大チェーン最上段をバイリニアで読む±0.5テクセル。
//!
//! **テクセルの大きさは段ごとにちょうど2倍にはならない。** 段の寸法は整数の除算で半分にするため、奇数の辺は
//! 端数を落とす。1280x720の段の寸法列は640x360・320x180・160x90・80x45・40x22であり、最下段の縦は45の半分の
//! 22.5でなく22である。したがって縦のテクセルは720割る22で32.727画素になり、横の32画素より大きい。倍々を仮定すると
//! 縦の届く範囲を1画素ぶん短く見積もる。上限は縦横それぞれで積み上げて大きい方を採る。
//!
//! 段の寸法から割り出したテクセルは整数にならないため、段ごとに切り上げてから積む。切り上げは上限を大きい側へ
//! 倒すだけであり、実在の届く範囲を短く見積もることはない。1280x720では横が2.5x(1+2+4+8+16)+1.5x(32+16+8+4)+1で
//! 168.5画素、縦が2.5x31+1.5x(33+16+8+4)+1で169.5画素であり、切り上げて170画素になる。標本位置が半テクセル刻みで
//! 出るため、半画素の単位で整数のまま積み上げてから最後に1度だけ切り上げる。
//! 参照: `shaders/bloom_filters.slang`(13タップとテントの標本位置)、`crates/blitz_render/src/vulkan/bloom_targets.rs`(段の寸法列)
//!
//! 注意: 段数上限と最小辺は`bloom_targets.rs`の写しであり、`cargo xtask conform`の定数の組が一致を見る。
//! 段が増える向きへ正本が動くと、写しのままの上限は実際より小さくなり判定が落ちる。見逃しでなく失敗になる
//! 向きであるため、ずれが静かに通ることはない。

#[cfg(test)]
mod footprint_tests;
mod source_distance;

const 段数上限: usize = 5;
const 最小辺PX: usize = 16;
const 縮小の半画素: usize = 5;
const 拡大の半画素: usize = 3;

pub(super) struct にじみの足跡 {
    上限: usize,
    発生源からの距離: Vec<usize>,
}

impl にじみの足跡 {
    pub(super) fn 求める(幅: usize, 高さ: usize, 発生源: &[bool]) -> Self {
        Self {
            上限: 画面距離の上限(幅, 高さ),
            発生源からの距離: source_distance::発生源からのチェビシェフ距離(幅, 高さ, 発生源),
        }
    }

    pub(super) fn 上限(&self) -> usize {
        self.上限
    }

    pub(super) fn 発生源からの距離(&self, 添字: usize) -> usize {
        self.発生源からの距離[添字]
    }
}

/// にじみピラミッドと同じ規則で並べた段の寸法列。長さは常に1以上であり、正本の`段の寸法列`と同じ整数の除算で半分にする。
pub(super) fn 段の寸法列(幅: usize, 高さ: usize) -> Vec<(usize, usize)> {
    let mut 一覧 = Vec::new();
    let (mut 段の幅, mut 段の高さ) = ((幅 / 2).max(1), (高さ / 2).max(1));
    loop {
        一覧.push((段の幅, 段の高さ));
        if 一覧.len() >= 段数上限 || 段の幅 / 2 < 最小辺PX || 段の高さ / 2 < 最小辺PX {
            return 一覧;
        }
        段の幅 /= 2;
        段の高さ /= 2;
    }
}

fn 画面距離の上限(幅: usize, 高さ: usize) -> usize {
    let 寸法列 = 段の寸法列(幅, 高さ);
    let 横 = 軸ごとの上限(幅, 寸法列.iter().map(|(段の幅, _)| *段の幅));
    let 縦 = 軸ごとの上限(高さ, 寸法列.iter().map(|(_, 段の高さ)| *段の高さ));
    横.max(縦)
}

/// 1つの軸について、その軸のテクセルの大きさを段ごとに切り上げて積む。返すのは切り上げ済みの画素数である。
fn 軸ごとの上限(全体の画素数: usize, 段の画素数列: impl Iterator<Item = usize>) -> usize {
    let テクセル: Vec<usize> = 段の画素数列.map(|段の画素数| 全体の画素数.div_ceil(段の画素数.max(1))).collect();
    let 最上段 = テクセル.first().copied().unwrap_or(2);
    let 縮小の読み元 = std::iter::once(1).chain(テクセル.iter().copied()).take(テクセル.len());
    let 縮小 = 縮小の読み元.map(|読み元| 縮小の半画素 * 読み元).sum::<usize>();
    let 拡大 = テクセル.iter().skip(1).map(|読み元| 拡大の半画素 * 読み元).sum::<usize>();
    (縮小 + 拡大 + 最上段).div_ceil(2)
}
