//! 光のにじみが1画素の変化を画面上どこまで運ぶかの上限と、変化の発生源から各画素までの画面距離。
//! 受け取るのは画面の寸法と発生源の画素集合、返すのは上限を知っていて距離を答える足跡である。
//!
//! 後処理ありの対で近傍の色が動くのは、遠景が地平の帯で明るい空を暗い地形へ置き換え、にじみが撒く光が
//! 減るためである。にじみは画面内の演算子であり台が遠景の輪郭より広いため、近傍不変は後処理込みでは
//! 原理的に達成できない。そこで「変化が発生源のにじみの足跡の内側に収まること」を代わりに課す。
//! 参照: `crates/blitz_app/src/reports/sky_pixel.rs`(にじみと明るさの圧縮が1画素の期待値を決めなくする既知の機構)
//!
//! 上限は3つの積み上げである。縮小は13タップが読み元の±2テクセルへ届き、バイリニアの標本がさらに
//! ±0.5テクセル広げるため1段あたり±2.5テクセル。拡大は3x3テントの±1テクセルとバイリニアの±0.5テクセルで
//! 1段あたり±1.5テクセル。最後に明るさの圧縮が拡大チェーン最上段をバイリニアで読む±0.5テクセル。
//! テクセルの大きさはフル解像度の画素で数え、段ごとに2倍になる。1280x720では縮小の積み上げが
//! 2.5x(1+2+4+8+16)=77.5画素、拡大が1.5x(32+16+8+4)=90画素、最後の標本が1画素で、
//! 合わせて168.5画素、切り上げて169画素になる。標本位置が半テクセル刻みで出るため、半画素の単位で
//! 整数のまま積み上げてから最後に1度だけ切り上げる。
//! 参照: `shaders/bloom_filters.slang`(13タップとテントの標本位置)、`crates/blitz_render/src/vulkan/bloom_targets.rs`(段の寸法列)
//!
//! 注意: 段数上限と最小辺は`bloom_targets.rs`の写しであり、`cargo xtask conform`の定数の組が一致を見る。
//! 段が増える向きへ正本が動くと、写しのままの上限は実際より小さくなり判定が落ちる。見逃しでなく失敗になる
//! 向きであるため、ずれが静かに通ることはない。

#[cfg(test)]
mod footprint_tests;
mod source_distance;

const 段数上限: usize = 5;
const 最小辺PX: usize = 16;
const 縮小の半画素: usize = 5;
const 拡大の半画素: usize = 3;

pub(super) struct にじみの足跡 {
    上限: usize,
    発生源からの距離: Vec<usize>,
}

impl にじみの足跡 {
    pub(super) fn 求める(幅: usize, 高さ: usize, 発生源: &[bool]) -> Self {
        Self {
            上限: 画面距離の上限(幅, 高さ),
            発生源からの距離: source_distance::発生源からのチェビシェフ距離(幅, 高さ, 発生源),
        }
    }

    pub(super) fn 上限(&self) -> usize {
        self.上限
    }

    pub(super) fn 足跡の外か(&self, 添字: usize) -> bool {
        self.発生源からの距離[添字] > self.上限
    }

    pub(super) fn 発生源からの距離(&self, 添字: usize) -> usize {
        self.発生源からの距離[添字]
    }
}

/// 段ごとのテクセルがフル解像度で何画素ぶんかを、にじみピラミッドと同じ規則で並べる。長さは常に1以上。
fn 段のテクセル幅一覧(幅: usize, 高さ: usize) -> Vec<usize> {
    let mut 一覧 = Vec::new();
    let (mut 段の幅, mut 段の高さ, mut テクセル幅) = ((幅 / 2).max(1), (高さ / 2).max(1), 2);
    loop {
        一覧.push(テクセル幅);
        if 一覧.len() >= 段数上限 || 段の幅 / 2 < 最小辺PX || 段の高さ / 2 < 最小辺PX {
            return 一覧;
        }
        段の幅 /= 2;
        段の高さ /= 2;
        テクセル幅 *= 2;
    }
}

fn 画面距離の上限(幅: usize, 高さ: usize) -> usize {
    let テクセル幅一覧 = 段のテクセル幅一覧(幅, 高さ);
    let 最上段のテクセル幅 = テクセル幅一覧.first().copied().unwrap_or(2);
    let 縮小の読み元 = std::iter::once(1).chain(テクセル幅一覧.iter().copied()).take(テクセル幅一覧.len());
    let 縮小 = 縮小の読み元.map(|読み元| 縮小の半画素 * 読み元).sum::<usize>();
    let 拡大 = テクセル幅一覧.iter().skip(1).map(|読み元| 拡大の半画素 * 読み元).sum::<usize>();
    (縮小 + 拡大 + 最上段のテクセル幅).div_ceil(2)
}
