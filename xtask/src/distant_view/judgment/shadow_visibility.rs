//! 影の欠落計器の診断を対照と候補で読み、画素ごとに影可視度が動いたかを答える対。
//! 受け取るのは採取の置き場、返すのは2枚を束ねた対である。
//!
//! 影可視度そのものの符号化と復号は`shadow_diagnostic_image`が持つ。ここが足すのは「2枚を突き合わせて
//! 動いたかを言う」ことだけである。
//!
//! 動いたとみなす下限を置くのは、影可視度がPCFの平均で連続の値を取り、8ビットへ量子化した往復で最下位の
//! 桁が揺れるためである。下限を0にすると、揺れだけの画素まで「動いた」と数えて帰属の検査が素通りする。
//! 逆に大きく取ると、薄い影の変化が「動いていない」ことになり、色だけが変わった画素として検査が落ちる。
//! 8ビットの1階調(1/255≒0.0039)を下回る変化は往復の揺れと区別できないため、その半分を下限に置く。

use std::path::Path;

use super::image_pair::検収画像;
use crate::shadow_diagnostic_image::診断画像;

/// 影可視度が動いたとみなす最小の差。線形の影可視度(0から1)で測る。
const 動いたとみなす影可視度の差: f64 = 0.002;

pub(super) struct 影可視度の対 {
    対照: 診断画像,
    候補: 診断画像,
}

impl 影可視度の対 {
    pub(super) fn 読む(置き場: &Path) -> Result<Self, String> {
        Ok(Self {
            対照: 診断の絵を読む(置き場, "shadow_reference_visibility")?,
            候補: 診断の絵を読む(置き場, "shadow_candidate_visibility")?,
        })
    }

    /// 色の対と同じ画素数であることを課す。違えば同じ添字が2枚で別の位置を指す。
    pub(super) fn 同じ画素数であることを課す(&self, 色の画素数: usize) -> Result<(), String> {
        if self.対照.画素数() == 色の画素数 && self.候補.画素数() == 色の画素数 {
            return Ok(());
        }
        Err(format!(
            "影可視度の診断の画素数が色の採取と違う(色{色の画素数}・対照{}・候補{})",
            self.対照.画素数(),
            self.候補.画素数()
        ))
    }

    /// 片方だけが幾何を持つ画素も「動いた」と数える。深度の一致を先に課しているためここへは来ないが、
    /// 来たときに黙って「動いていない」側へ倒すと、幾何のずれが色差の帰属をすり抜ける。
    pub(super) fn 影可視度が変わったか(&self, 添字: usize) -> bool {
        match (self.対照.画素(添字), self.候補.画素(添字)) {
            (Some(対照), Some(候補)) => (対照.影可視度 - 候補.影可視度).abs() >= 動いたとみなす影可視度の差,
            (None, None) => false,
            _ => true,
        }
    }

    pub(super) fn 影可視度が変わった画素数(&self) -> usize {
        (0..self.対照.画素数()).filter(|添字| self.影可視度が変わったか(*添字)).count()
    }
}

/// 採取が書いた提示色の対の2ファイルを、起動を伴わずにそのまま読み直して診断として復号する。
fn 診断の絵を読む(置き場: &Path, 名前: &str) -> Result<診断画像, String> {
    let 絵 = 検収画像::読む(置き場, 名前)?;
    Ok(診断画像::rgba8から読み取る(絵.幅, 絵.高さ, &絵.色))
}
