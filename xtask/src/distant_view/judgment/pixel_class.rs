//! 対照と候補の深度から画素を区分し、差が出てよい許可域を決める工程。受け取るのは対照と候補の検収画像、
//! 返すのは画素ごとの区分である。
//!
//! 許可域をここ1箇所で決めるのは、主判定(後処理なしの対)と有界検査(後処理ありの対)が同じ区分の上へ
//! 別の厳しさを課すためである。区分が2つに割れると、2段の判定が別の画素集合を見ることになり、
//! 片方で通ってもう片方で落ちたときにどちらの規則が違うのかを追えなくなる。

use super::contour;
use super::image_pair::検収画像;

pub(super) struct 画素の区分 {
    免除: Vec<bool>,
    対照幾何: Vec<bool>,
    候補幾何: Vec<bool>,
}

impl 画素の区分 {
    /// 免除は対照の幾何輪郭を2画素広げた帯である。遠景が背景へ現れる縁では、近傍の縁の画素が
    /// 標本の位置の丸めで1画素ぶん動きうるため、そこを不変の要求から外す。
    pub(super) fn 求める(対照: &検収画像, 候補: &検収画像) -> Self {
        Self {
            免除: contour::輪郭を二画素広げる(対照),
            対照幾何: (0..対照.画素数()).map(|添字| 対照.深度[添字] > 0.0).collect(),
            候補幾何: (0..候補.画素数()).map(|添字| 候補.深度[添字] > 0.0).collect(),
        }
    }

    pub(super) fn 画素数(&self) -> usize {
        self.免除.len()
    }

    /// 対照に幾何があり免除帯の外にある画素。第5段階の検査点4が不変を要求する近傍チャンクの幾何画素である。
    pub(super) fn 近傍か(&self, 添字: usize) -> bool {
        self.対照幾何[添字] && !self.免除[添字]
    }

    /// 差が出てよい範囲の外。近傍の画素と、対照でも候補でも背景のままの画素がこれに当たる。
    /// 遠景が背景を置き換えた画素と免除帯だけが許可域である。
    pub(super) fn 許可域の外か(&self, 添字: usize) -> bool {
        !self.免除[添字] && (self.対照幾何[添字] || !self.候補幾何[添字])
    }

    /// 対照では背景であり候補では幾何になった画素。遠景が実際に絵へ現れた証拠であり、
    /// 後処理のにじみが撒く変化の唯一の発生源でもある。
    pub(super) fn 遠景が背景を置き換えたか(&self, 添字: usize) -> bool {
        !self.対照幾何[添字] && self.候補幾何[添字]
    }

    pub(super) fn 候補幾何か(&self, 添字: usize) -> bool {
        self.候補幾何[添字]
    }

    /// 色差の工程へ貸す真偽の並び。工程を遠景と散布で共有するため、区分の読み方でなく並びで渡す。
    pub(super) fn 許可域の外の一覧(&self) -> Vec<bool> {
        (0..self.画素数()).map(|添字| self.許可域の外か(添字)).collect()
    }

    pub(super) fn 近傍の一覧(&self) -> Vec<bool> {
        (0..self.画素数()).map(|添字| self.近傍か(添字)).collect()
    }
}
