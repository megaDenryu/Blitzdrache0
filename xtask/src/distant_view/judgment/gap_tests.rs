//! 背景の斜め接触と、閉じた穴を位相で見分ける反証。
//!
//! 上辺以外の画面端へ届く穴を見逃さないことも見る。空と繋がるかを4辺すべてで見ていた実装は、
//! 地平線が画面の上3分の1にある固定構図で、左右と下の辺へ届いた実在の穴を空へ繋がるものとして落としていた。

use super::gap::閉じた先読み縁の空隙画素を数える;
use super::image_pair::検収画像;

#[test]
fn 画面端へ繋がる地平線の角は空隙でない() {
    let mut 対照深度 = vec![0.0; 25];
    let mut 候補深度 = vec![0.0; 25];
    for x in 2..5 {
        対照深度[20 + x] = 0.5;
        候補深度[20 + x] = 0.5;
    }
    候補深度[20] = 0.25;
    候補深度[21] = 0.25;
    assert_eq!(閉じた先読み縁の空隙画素を数える(&画像(5, 5, 対照深度), &画像(5, 5, 候補深度)), 0);
}

#[test]
fn 近傍と新遠景に囲まれた閉背景は空隙である() {
    let mut 対照深度 = vec![0.0; 9];
    let mut 候補深度 = vec![0.25; 9];
    候補深度[4] = 0.0;
    for 添字 in [2, 5, 6, 7, 8] {
        対照深度[添字] = 0.5;
        候補深度[添字] = 0.5;
    }
    assert_eq!(閉じた先読み縁の空隙画素を数える(&画像(3, 3, 対照深度), &画像(3, 3, 候補深度)), 1);
}

/// 左辺と下辺へ届く穴も空隙である。地平線が画面の上3分の1にある固定構図では、画面の左右と下の辺へ届く背景は
/// 画面外の空ではなく地面の側であり、そこへ届いたことを理由に見逃すと横へ長い穴が丸ごと落ちる。
#[test]
fn 上辺以外の画面端へ届く穴は空隙である() {
    let 幅 = 5;
    let 高さ = 5;
    let mut 対照深度 = vec![0.0; 幅 * 高さ];
    let mut 候補深度 = vec![0.0; 幅 * 高さ];
    // 上2行は空のまま残し、3行目を背景の穴にする。その上下を近傍と遠景で挟み、穴は左辺へ届く。
    for x in 0..幅 {
        対照深度[幅 + x] = 0.5;
        候補深度[幅 + x] = 0.5;
        候補深度[3 * 幅 + x] = 0.25;
    }
    let 数 = 閉じた先読み縁の空隙画素を数える(&画像(幅, 高さ, 対照深度), &画像(幅, 高さ, 候補深度));
    assert_eq!(数, 幅, "左辺へ届く穴が空隙として数えられていない");
}

fn 画像(幅: usize, 高さ: usize, 深度: Vec<f32>) -> 検収画像 {
    検収画像 {
        幅,
        高さ,
        色: vec![0; 幅 * 高さ * 4],
        深度,
    }
}
