//! 旗1つぶんの2状態の綴り。受け取るのは真偽または旗の欄の綴り、返すのは綴りまたは読み取った真偽である。
//!
//! 綴りを`on`と`off`に固定し、読めない綴りを黙って偽へ倒さない。倒すと、綴りを書き誤った採取が
//! 「切ってある」という意味に化けて判定を通り抜ける。

pub(super) fn 入切(使うか: bool) -> &'static str {
    if 使うか { "on" } else { "off" }
}

/// 2状態のどちらでもない綴りは読み取れないものとして返す。読み取れないことの扱いは呼び出し側が決める。
pub(super) fn 入切の綴りを読む(綴り: &str) -> Option<bool> {
    match 綴り {
        "on" => Some(true),
        "off" => Some(false),
        _ => None,
    }
}
