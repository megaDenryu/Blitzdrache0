//! 旗1つぶんの2状態の文字列。受け取るのは真偽または旗の欄の文言、返すのは文字列または読み取った真偽である。
//!
//! 文字列を`on`と`off`に固定し、読めない文字列を黙って偽へ倒さない。倒すと、文字列を書き誤った採取が
//! 「切ってある」という意味に化けて判定を通り抜ける。

pub(super) fn 入切(使うか: bool) -> &'static str {
    if 使うか { "on" } else { "off" }
}

/// 2状態のどちらでもない文字列は読み取れないものとして返す。読み取れないことの扱いは呼び出し側が決める。
pub(super) fn 入切の文字列を読む(文字列: &str) -> Option<bool> {
    match 文字列 {
        "on" => Some(true),
        "off" => Some(false),
        _ => None,
    }
}
