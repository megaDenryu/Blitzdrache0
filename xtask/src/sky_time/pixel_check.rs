//! 空代表画素(`--report-sky-pixel`)の照合をsky-timeへ組み込む工程。担当するのは「領域区分から天頂寄りと
//! 地平線直上の2画素を選び、その画素についてCPU正本の期待値と読み戻し画像の実測値を突き合わせる」ことである。
//!
//! 条件は`再描画する添字`と同じ正午を使う。空も地表も明るく、丸め誤差が最も見えやすい条件だからである。
//! 終了時報告から行を切り出す部分は`parse`が持つ。

mod parse;

use parse::代表画素行;

use super::draw::描いて報告も得る;
use super::moment;
use super::region::領域区分;
use super::run::条件;
use crate::acceptance::{判定の名前, 描画検収の実行環境, 検収エラー};

/// sRGB8bit相当の期待値と実測値の差に許す絶対誤差。2026-07-30の実測(正午・列640・天頂寄り縦3・地平線直上縦311)は
/// 最大0.35階調であり、丸めの余地を持たせてその6倍を取る。
const 許容誤差: f64 = 2.0;
/// 天頂側・地平線側それぞれで境界から外す行数。フレーム上端の切り詰めや地平線の縁のにじみを避ける。
const 余白行数: usize = 3;
/// 照合する代表画素の本数。天頂寄りと地平線直上の2点である。
const 代表画素の本数: usize = 2;

const 空代表画素の行の本数: 判定の名前 = 判定の名前::定数から生成する("報告が出した空代表画素の行の本数");

pub(super) fn 照合する(実行環境: &描画検収の実行環境, 幅: usize, 区分: &領域区分) -> Result<(), 検収エラー> {
    let 列 = 幅 / 2;
    let Some((先頭, 末尾)) = 区分.縦の空範囲を求める(幅, 列) else {
        return Err(列の空画素の判定名(列).あるはずのものが無い破れ().into());
    };
    空領域の末尾行の判定名(列, 先頭).下限を課す(末尾, 先頭 + 余白行数 * 2 + 1)?;
    let 画素引数 = format!("{列},{}", 先頭 + 余白行数) + &format!(";{列},{}", 末尾 - 余白行数);

    let 正午 = &moment::代表時刻一覧[moment::再描画する添字];
    let 実行 = 描いて報告も得る(
        実行環境,
        "pixel_check",
        &条件::時刻の絵 {
            一日内秒: 正午.一日内秒,
            カメラ方位度: "0",
        },
        // `--report-sky-pixel`のCPU正本は光のにじみ・露出・ACES明るさの圧縮を通さない前提で線形放射輝度を
        // sRGB符号化する(参照: `crates/blitz_app/src/reports/sky_pixel.rs`冒頭)。描画側もポスト処理を外す。
        &["--report-sky-pixel", &画素引数, "--no-post"],
    )?;
    let 行一覧 = parse::読み取る(実行.報告())?;
    空代表画素の行の本数.一致を課す(行一覧.len(), 代表画素の本数)?;
    for 行 in &行一覧 {
        判定する(行)?;
    }
    Ok(())
}

fn 判定する(行: &代表画素行) -> Result<(), 検収エラー> {
    for (添字, 名) in ["赤", "緑", "青"].into_iter().enumerate() {
        let 差 = (行.期待[添字] - 行.実測[添字]).abs();
        成分の差の判定名(行, 添字, 名).上限を課す(差, 許容誤差)?;
    }
    Ok(())
}

fn 列の空画素の判定名(列: usize) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("列{列}にある空の画素"))
}

fn 空領域の末尾行の判定名(列: usize, 先頭: usize) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "列{列}の空領域の末尾行(先頭{先頭}から余白{余白行数}行を両端に取るために要る下限)"
    ))
}

fn 成分の差の判定名(行: &代表画素行, 添字: usize, 名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "画素({}, {})の{名}成分の期待{:.2}と実測{:.2}の差",
        行.横, 行.縦, 行.期待[添字], 行.実測[添字]
    ))
}
