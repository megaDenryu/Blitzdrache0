//! 検収1条件ぶんの起動の指定。受け取るのは条件と条件別に足す選択肢、返すのは実行環境へ渡す起動指定である。
//! 起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! 地形世界は空を持つ方針であるため、時刻の絵は本番の経路で描く。自動露出だけは`--no-auto-exposure`で外す。この入口が見るのは時刻から導く照明そのもの(夜の地表が環境光だけの帯・隣り合う時刻の明るさの変化・夜明けと夕方の対称性)であり、自動露出を通した最終色は「照明÷露出」になってその3つを測れなくなるためである。時間再構成も`--no-taa`で外す。この入口の判定はバイト一致に依るため、フレームをまたぐ混合が入ると隣り合う時刻の比較が混合の残りを含む。
//! 領域マスクだけは空とポスト処理とライティングを外し、地表が白・背景がクリア色になる条件で撮る。
//! 地形世界は本番のストリーミング経路でしか地面が現れないため、先読み半径と容量上限をOW3の統合経路と同じ値で渡す。カメラはシーン既定の見下ろし35度から25度戻し、地平線より上を画面へ入れる(`sky-draw`と同じ構図)。

use std::path::PathBuf;

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収エラー, 検収シーン名
};

const アセットルート: &str = "target/terrain_assets";
const シーン名: 検収シーン名 = 検収シーン名::生成する("terrain_origin");
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(160);
const 先読み半径: &str = "2";
const 容量上限バイト: &str = "16777216";
const カメラ俯角差分度: &str = "-25";

/// `領域マスク`のカメラ方位度は、判定に使う絵と同じ角度でなければ区分と絵の画素が対応しない。
pub(super) enum 条件<'引数> {
    時刻の絵 {
        一日内秒: &'引数 str,
        カメラ方位度: &'引数 str,
    }, // 本番の経路でその時刻の絵を描く。カメラ方位は既定の0度から動かす角度である
    領域マスク {
        カメラ方位度: &'引数 str,
    }, // 空も光も外して、どの画素が空でどの画素がジオメトリかだけを撮る
}

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::綴りから生成する(アセットルート),
        出力ディレクトリ,
    )
}

pub(super) fn 起動指定を組み立てる(条件: &条件<'_>, 追加の選択肢: &[&str]) -> アプリの起動指定 {
    let 指定 = アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数)
        .選択肢を足す("--streaming")
        .値を持つ選択肢を足す("--streaming-preload-radius", 先読み半径)
        .値を持つ選択肢を足す("--streaming-ram-limit", 容量上限バイト)
        .値を持つ選択肢を足す("--streaming-vram-limit", 容量上限バイト)
        .値を持つ選択肢を足す("--camera-pitch", カメラ俯角差分度)
        .選択肢を足す("--no-taa");
    条件別の選択肢を足す(指定, 条件).選択肢をまとめて足す(追加の選択肢)
}

fn 条件別の選択肢を足す(指定: アプリの起動指定, 条件: &条件<'_>) -> アプリの起動指定 {
    match 条件 {
        条件::時刻の絵 {
            一日内秒, カメラ方位度
        } => 指定
            .値を持つ選択肢を足す("--time-of-day", 一日内秒)
            .値を持つ選択肢を足す("--camera-yaw", カメラ方位度)
            .選択肢を足す("--no-auto-exposure"),
        条件::領域マスク { カメラ方位度 } => 指定
            .選択肢をまとめて足す(&["--no-sky", "--no-post", "--unlit"])
            .値を持つ選択肢を足す("--camera-yaw", カメラ方位度),
    }
}
