//! 検収の実測値を人が読める形で出す工程。受け取るのは時刻の名前と実測値、出すのは表と絵である。
//! 親エージェントの検収は絵の目視を含むため、判定の合否とは別に4時刻と太陽円盤のPNGを必ず書き出す。
//!
//! 表を判定より先に出すのは、判定値を実測から更新するときに落ちた実行の実測がすべて要るためである。
//! 判定の後ろに置くと、1つ目の判定が落ちた時点で残りの実測が1つも見えない。

use std::path::Path;

use super::moment;
use super::stats::領域別実測;
use crate::acceptance::検収エラー;

pub(super) fn 表を出す(名前一覧: &[&str], 実測一覧: &[領域別実測]) {
    println!("時刻別の領域実測(空の平均色、明部p95、明部p99、暗部画素数、地形の黒潰れ・飽和・全成分0の画素数):");
    for (名前, 実測) in 名前一覧.iter().zip(実測一覧) {
        let [赤, 緑, 青] = 実測.空平均色;
        println!(
            "  {名前}: 空({赤}, {緑}, {青}) 明部p95={} 明部p99={} 暗部={} 地形の黒潰れ={} 地形の飽和={} 全成分0={}",
            実測.明部p95, 実測.明部p99, 実測.暗部画素数, 実測.地形の黒潰れ画素数, 実測.地形の飽和画素数, 実測.黒つぶれ画素数
        );
    }
}

pub(super) fn 絵を書き出す(出力先: &Path) -> Result<String, 検収エラー> {
    let ファイル名一覧 = moment::代表時刻一覧
        .iter()
        .map(|時刻| 時刻.ファイル名)
        .chain([moment::太陽円盤のファイル名, moment::太陽円盤対照のファイル名]);
    let mut 置き場 = Vec::new();
    for ファイル名 in ファイル名一覧 {
        置き場.push(一枚を目視用の絵へ変換する(&出力先.join(ファイル名))?.display().to_string());
    }
    Ok(置き場.join("、"))
}

/// 変換の失敗を検収エラーの枝へ載せる。この入口は書き出し先を絵の置き場から組み立てるため、
/// 読み戻しの置き場の型を通らず、変換の破れを自分で包む。
fn 一枚を目視用の絵へ変換する(書き出し先: &Path) -> Result<std::path::PathBuf, 検収エラー> {
    crate::raw_png::変換する(書き出し先).map_err(|破れ| 検収エラー::目視用の絵へ変換できなかった {
        書き出し先: 書き出し先.to_path_buf(),
        破れ,
    })
}
