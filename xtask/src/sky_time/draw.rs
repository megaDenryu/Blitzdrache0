//! 検収が必要とする絵をすべて描く工程。受け取るのは出力先、返すのは判定が読む絵の束である。
//! どの条件を何枚撮るかを決めるのはこの工程だけであり、判定側は撮り方を知らない。
//! 太陽円盤の明るさだけを変えた対の撮影は`sun_disk_pair`が持つ。

pub(super) mod sun_disk_pair;

use super::moment;
use super::run::{条件, 起動指定を組み立てる};
use crate::acceptance::{描画検収の実行環境, 検収の実行名, 読み戻し画像};
use sun_disk_pair::円盤の対;

pub(super) struct 絵の束 {
    pub(super) 時刻ごと: Vec<読み戻し画像>,
    /// 決定性を測るための同一時刻の2枚目。
    pub(super) 再描画: 読み戻し画像,
    /// 太陽円盤の放射輝度だけを0にした対と、その構図の領域区分。
    pub(super) 円盤: 円盤の対,
}

pub(super) fn 領域マスクを撮る(実行環境: &描画検収の実行環境) -> Result<読み戻し画像, String> {
    描く(実行環境, "region_mask", &条件::領域マスク { カメラ方位度: "0" }, &[])
}

pub(super) fn 絵を撮る(実行環境: &描画検収の実行環境) -> Result<絵の束, String> {
    let mut 時刻ごと = Vec::new();
    for 時刻 in &moment::代表時刻一覧 {
        時刻ごと.push(描く(実行環境, 時刻.ファイル名, &正面から見る(時刻.一日内秒), &[])?);
    }
    let 再描画の時刻 = &moment::代表時刻一覧[moment::再描画する添字];
    let 再描画 = 描く(
        実行環境,
        &format!("{}_repeat", 再描画の時刻.ファイル名),
        &正面から見る(再描画の時刻.一日内秒),
        &[],
    )?;
    Ok(絵の束 {
        時刻ごと,
        再描画,
        円盤: sun_disk_pair::撮る(実行環境)?,
    })
}

/// 1条件を描いて絵だけを取り出す。報告の行を読む条件は`描いて報告も得る`を使う。
pub(in crate::sky_time) fn 描く(
    実行環境: &描画検収の実行環境,
    実行名の綴り: &str,
    条件: &条件<'_>,
    追加の選択肢: &[&str],
) -> Result<読み戻し画像, String> {
    描いて報告も得る(実行環境, 実行名の綴り, 条件, 追加の選択肢).map(|(画像, _)| 画像)
}

/// 追加の選択肢を足したうえで描き、画素と報告の本文の両方を返す。空代表画素の照合(`--report-sky-pixel`)のように
/// 画像だけでなく報告の行も読みたい呼び出し元のための入口である。
pub(in crate::sky_time) fn 描いて報告も得る(
    実行環境: &描画検収の実行環境,
    実行名の綴り: &str,
    条件: &条件<'_>,
    追加の選択肢: &[&str],
) -> Result<(読み戻し画像, String), String> {
    let 実行 = 実行環境.描いて読み戻す(検収の実行名::生成する(実行名の綴り)?, &起動指定を組み立てる(条件, 追加の選択肢))?;
    let 本文 = 実行.報告().本文().to_string();
    Ok((実行.画像を取り出す(), 本文))
}

/// 4時刻はすべて同じ構図で撮る。構図が変わると領域マスクが使えず、時刻の違いと構図の違いを分けられない。
fn 正面から見る(一日内秒: &str) -> 条件<'_> {
    条件::時刻の絵 {
        一日内秒, カメラ方位度: "0"
    }
}
