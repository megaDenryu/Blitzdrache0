//! 検収が必要とする絵をすべて描く工程。受け取るのは出力先、返すのは判定が読む絵の束である。
//! どの条件を何枚撮るかを決めるのはこの工程だけであり、判定側は撮り方を知らない。

use std::path::Path;

use super::moment;
use super::run::{実行結果, 描画する, 条件};

pub(super) struct 絵の束 {
    pub(super) 時刻ごと: Vec<実行結果>,
    /// 決定性を測るための同一時刻の2枚目。
    pub(super) 再描画: 実行結果,
    pub(super) 太陽円盤: 実行結果,
    /// 太陽円盤の判定が使う負の対照。同じ時刻・同じ構図で太陽だけを画面の外へ出した絵である。
    pub(super) 太陽円盤対照: 実行結果,
}

pub(super) fn 領域マスクを撮る(出力先: &Path) -> Result<実行結果, String> {
    描画する(出力先, "region_mask", &条件::領域マスク)
}

pub(super) fn 絵を撮る(出力先: &Path) -> Result<絵の束, String> {
    let mut 時刻ごと = Vec::new();
    for 時刻 in &moment::代表時刻一覧 {
        時刻ごと.push(描画する(出力先, 時刻.ファイル名, &正面から見る(時刻.一日内秒))?);
    }
    let 再描画の時刻 = &moment::代表時刻一覧[moment::再描画する添字];
    let 再描画 = 描画する(
        出力先,
        &format!("{}_repeat", 再描画の時刻.ファイル名),
        &正面から見る(再描画の時刻.一日内秒),
    )?;
    let 太陽円盤 = 描画する(
        出力先,
        moment::太陽円盤のファイル名,
        &条件::時刻の絵 {
            一日内秒: moment::太陽円盤の一日内秒,
            カメラ方位度: moment::太陽円盤のカメラ方位度,
        },
    )?;
    let 太陽円盤対照 = 描画する(
        出力先,
        moment::太陽円盤対照のファイル名,
        &条件::時刻の絵 {
            一日内秒: moment::太陽円盤の一日内秒,
            カメラ方位度: moment::太陽円盤対照のカメラ方位度,
        },
    )?;
    Ok(絵の束 {
        時刻ごと,
        再描画,
        太陽円盤,
        太陽円盤対照,
    })
}

/// 4時刻はすべて同じ構図で撮る。構図が変わると領域マスクが使えず、時刻の違いと構図の違いを分けられない。
fn 正面から見る(一日内秒: &str) -> 条件<'_> {
    条件::時刻の絵 {
        一日内秒, カメラ方位度: "0"
    }
}
