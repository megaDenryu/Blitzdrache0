//! 読み戻し画像そのものを読む判定。担当するのは、領域区分も統計も通さずに画素を直接見る2つである。
//! 同一時刻の2枚をバイト列のまま比べる決定性の判定と、画面全体から高輝度画素を数える太陽円盤の判定であり、
//! どちらも領域別の実測値を必要としない。

use super::draw::絵の束;
use super::moment;
use super::run::実行結果;
use super::stats::{円盤の明るさ下限, 明るさ下限以上の画素数};

/// 太陽円盤の画素数に許す上限。角半径0.27度の円盤は1280x720の画角で数十画素であり、
/// 空全体が白へ飛んだ状態をこの上限が落とす。
const 円盤画素数の上限: u64 = 2_000;

/// 同一時刻を2回描いた結果がバイト一致することを確かめる。
pub(super) fn 決定性を判定する(絵: &絵の束) -> Result<(), String> {
    let 時刻 = &moment::代表時刻一覧[moment::再描画する添字];
    if 絵.再描画.バイト列() != 絵.時刻ごと[moment::再描画する添字].バイト列() {
        return Err(format!("{}を2回描いた結果がバイト一致しなかった", 時刻.名前));
    }
    Ok(())
}

/// 低い太陽の条件で太陽円盤の高輝度画素が現れることを確かめる。返すのは数えた画素数である。
/// 太陽円盤は領域マスクと別のカメラ方位で撮るため、画面全体から数える。
pub(super) fn 太陽円盤を判定する(絵: &実行結果) -> Result<u64, String> {
    let 画素数 = 明るさ下限以上の画素数(絵, 円盤の明るさ下限);
    if 画素数 == 0 {
        return Err("夕方の低い太陽で高輝度の画素が1つも現れなかった".to_string());
    }
    if 画素数 > 円盤画素数の上限 {
        return Err(format!("高輝度の画素が{画素数}個あり、上限{円盤画素数の上限}を超える"));
    }
    Ok(画素数)
}
