//! 読み戻し画像そのものを読む判定。担当するのは、領域区分も統計も通さずに画素を直接見る2つである。
//! 同一時刻の2枚をバイト列のまま比べる決定性の判定と、太陽円盤の対照(同一時刻・同一カメラで円盤の放射輝度
//! だけを0にした絵)との画素位置ごとの差分を数える太陽円盤の判定であり、どちらも領域別の実測値を必要としない。

use super::draw::絵の束;
use super::moment;
use super::sun_disk_diff;

/// 太陽円盤ありと対照の差分画素数に許す帯。角半径0.27度の円盤は、縦視野60度を720画素で割った
/// 1度あたり12画素相当を半径に掛けた幾何面積がπ×(0.27×12)^2≈33画素であり、2026-07-30の実測(32画素)と
/// 近い値になる。丸めと大気減光による目減り・アンチエイリアシングとブルームの縁による膨らみの両方に
/// 余裕を持たせ、見込み面積のおよそ4分の1から4倍を帯に取る。
const 差分の下限: u64 = 8;
const 差分の上限: u64 = 128;

/// 差分画素の外接矩形の面積に許す、差分画素数に対する倍率の上限。正方形に内接する円の面積比(π/4)の
/// 逆数はおよそ1.27であり、円形の円盤なら外接矩形はこの程度で収まる。ブルームの縁のにじみにも余裕を
/// 持たせて4倍を取る。円盤と無関係な画素が1つでも遠くに混じると、外接矩形だけが不釣り合いに広がって
/// この倍率を超える。
const 外接矩形面積倍率の上限: u64 = 4;

/// 同一時刻を2回描いた結果がバイト一致することを確かめる。
pub(super) fn 決定性を判定する(絵: &絵の束) -> Result<(), String> {
    let 時刻 = &moment::代表時刻一覧[moment::再描画する添字];
    if 絵.再描画.バイト列() != 絵.時刻ごと[moment::再描画する添字].バイト列() {
        return Err(format!("{}を2回描いた結果がバイト一致しなかった", 時刻.名前));
    }
    Ok(())
}

/// 低い太陽の条件で太陽円盤の画素が現れることを、対照との画素位置ごとの差分で確かめる。返すのは差分画素数である。
///
/// 対照はカメラを動かさない。カメラを反対へ振って構図ごと変える旧設計は、地形・空・霞を含む全画素の視線が
/// 変わるため、画面全体の高輝度画素数を単独の上下限だけで見る判定しか作れず、円盤の位置を1度も見ない
/// (円盤が消えて円盤と無関係な飽和画素が代わりに現れる退行を通してしまう)。構図を1画素も動かさず起動指定
/// `--sun-disk-off`で円盤の放射輝度だけを0にすると、円盤以外の画素は決定的に同じ値になり、差分は円盤と
/// その周りのブルームだけに残る。差分画素数を見込み面積の帯で判定するのに加え、差分画素が1つの塊に
/// まとまっていることを外接矩形の面積で判定する。円盤と無関係な離れた画素が1つでも混じれば、
/// 外接矩形だけが不釣り合いに広がって落ちる。
pub(super) fn 太陽円盤を判定する(絵: &絵の束) -> Result<u64, String> {
    let 差分 = sun_disk_diff::求める(&絵.太陽円盤, &絵.太陽円盤対照)?;
    if !(差分の下限..=差分の上限).contains(&差分.差分画素数) {
        return Err(format!(
            "太陽円盤ありと対照の差分画素数が{}で、期待帯{差分の下限}から{差分の上限}に収まらない",
            差分.差分画素数
        ));
    }
    let 外接矩形面積 = u64::try_from(差分.外接矩形の幅 * 差分.外接矩形の高さ).unwrap_or(u64::MAX);
    if 外接矩形面積 > 外接矩形面積倍率の上限 * 差分.差分画素数 {
        return Err(format!(
            "太陽円盤の差分画素{}個に対して外接矩形が{}x{}({外接矩形面積}画素)と広すぎ、円盤と無関係な画素が混じっている疑いがある",
            差分.差分画素数, 差分.外接矩形の幅, 差分.外接矩形の高さ
        ));
    }
    Ok(差分.差分画素数)
}
