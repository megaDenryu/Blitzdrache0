//! 読み戻し画像そのものを読む判定。担当するのは、領域区分も統計も通さずに画素を直接見る2つである。
//! 同一時刻の2枚をバイト列のまま比べる決定性の判定と、太陽が画面外の対照との差分で高輝度画素を数える
//! 太陽円盤の判定であり、どちらも領域別の実測値を必要としない。

use super::draw::絵の束;
use super::moment;
use super::stats::{円盤の明るさ下限, 明るさ下限以上の画素数};

/// 対照(太陽が画面外の構図)自体に許す高輝度画素数の上限。0にしないのは、対照の絵にも地形の反射など
/// 円盤と無関係な明部がわずかに乗る余地を残すためである。円盤の見込み面積(後述)よりずっと小さい値を取り、
/// 対照側に円盤級の飽和が紛れ込んだ実行を落とす。
const 対照画素数の上限: u64 = 8;
/// 太陽円盤ありと対照の高輝度画素数の差に許す帯。角半径0.27度の円盤は、縦視野60度を720画素で割った
/// 1度あたり12画素相当を半径に掛けた幾何面積がπ×(0.27×12)^2≈33画素であり、2026-07-30の実測(32画素)と
/// 近い値になる。丸めと大気減光による目減り・アンチエイリアシングとブルームの縁による膨らみの両方に
/// 余裕を持たせ、見込み面積のおよそ4分の1から4倍を帯に取る。
const 差分の下限: u64 = 8;
const 差分の上限: u64 = 128;

/// 同一時刻を2回描いた結果がバイト一致することを確かめる。
pub(super) fn 決定性を判定する(絵: &絵の束) -> Result<(), String> {
    let 時刻 = &moment::代表時刻一覧[moment::再描画する添字];
    if 絵.再描画.バイト列() != 絵.時刻ごと[moment::再描画する添字].バイト列() {
        return Err(format!("{}を2回描いた結果がバイト一致しなかった", 時刻.名前));
    }
    Ok(())
}

/// 低い太陽の条件で太陽円盤の高輝度画素が現れることを、円盤なしの対照との差分で確かめる。返すのは差分である。
///
/// 画面全体の高輝度画素数を単独の上限・下限だけで見る判定は、円盤の位置を1度も見ないため、円盤が消えて
/// 円盤と無関係な飽和画素が代わりに現れる退行を通してしまう。太陽の向きだけを180度変えた対照(`絵の束`の
/// `太陽円盤対照`。太陽が画面に絶対入らないことは`moment`のカメラ方位の根拠が角度で保証する)を同じ時刻・
/// 同じ構図で撮り、円盤の寄与だけを差分として取り出す。空全体の白飛びのような円盤と無関係な飽和は対照側にも
/// 同じだけ乗るため、差分を取れば打ち消える。
pub(super) fn 太陽円盤を判定する(絵: &絵の束) -> Result<u64, String> {
    let 円盤画素数 = 明るさ下限以上の画素数(&絵.太陽円盤, 円盤の明るさ下限);
    let 対照画素数 = 明るさ下限以上の画素数(&絵.太陽円盤対照, 円盤の明るさ下限);
    if 対照画素数 > 対照画素数の上限 {
        return Err(format!(
            "太陽が画面外の対照にすでに高輝度画素が{対照画素数}個あり、上限{対照画素数の上限}を超える(円盤以外の飽和が疑われる)"
        ));
    }
    let 差分 = 円盤画素数
        .checked_sub(対照画素数)
        .ok_or_else(|| format!("対照の高輝度画素数{対照画素数}が円盤ありの{円盤画素数}を上回った"))?;
    if !(差分の下限..=差分の上限).contains(&差分) {
        return Err(format!(
            "太陽円盤ありと対照の高輝度画素数の差が{差分}で、期待帯{差分の下限}から{差分の上限}に収まらない(円盤あり{円盤画素数}・対照{対照画素数})"
        ));
    }
    Ok(差分)
}
