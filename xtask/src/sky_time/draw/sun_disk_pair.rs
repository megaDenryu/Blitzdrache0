//! 太陽円盤の明るさだけを変えた対の撮影。担当するのは「同じ時刻・同じカメラで円盤ありと円盤なしの絵を
//! ポスト処理ありと無しで1組ずつ撮り、その構図の領域区分も作る」ことである。受け取るのは出力先、
//! 返すのは判定が読む4枚と領域区分と2つの標準出力である。
//!
//! ポスト処理を外した組を別に撮るのは、ポスト処理の光のにじみが円盤の明るさを画面の広い範囲へ数階調ぶん運び、
//! 地形の画素までバイトを動かすためである。にじみは間接照明の経路を通らないため、これを含めたまま
//! 「円盤の明るさが間接照明へ入っていない」ことを画素で言うことはできない。
//!
//! 標準出力を持つのは、遠方環境の鍵と焼き直しの判断が対で同じであることを行の一致で確かめるためである。

use std::path::Path;

use super::super::moment;
use super::super::region::領域区分;
use super::super::run::{実行結果, 描画して標準出力も得る, 描画する, 条件};

/// 円盤の明るさだけが違う対と、その構図の領域区分。
pub(in crate::sky_time) struct 円盤の対 {
    pub(in crate::sky_time) ポストあり: 実行結果,
    pub(in crate::sky_time) ポストあり対照: 実行結果,
    /// ポスト処理を外した円盤ありの絵。地形の表面画素のバイト一致をこの組で見る。
    pub(in crate::sky_time) ポスト無し: 実行結果,
    pub(in crate::sky_time) ポスト無し対照: 実行結果,
    /// この構図で、どの画素が空でどの画素が地形かの区分。
    pub(in crate::sky_time) 領域区分: 領域区分,
    pub(in crate::sky_time) 標準出力: String,
    pub(in crate::sky_time) 対照の標準出力: String,
}

/// 遠方環境の鍵と焼き直しの判断を報告させる指定。ポストありの組だけに足すのは、対の間で行を比べるのに
/// 1組あれば足りるためである。
const 報告の指定: &str = "--report-atmosphere-passes";
/// 太陽円盤の放射輝度だけを0へ差し替える指定。カメラも時刻も動かさない。
const 円盤を消す指定: &str = "--sun-disk-off";
/// ポスト処理を外す指定。
const ポストを外す指定: &str = "--no-post";

pub(in crate::sky_time) fn 撮る(出力先: &Path) -> Result<円盤の対, String> {
    let (ポストあり, 標準出力) = 円盤の条件で撮る(出力先, moment::太陽円盤のファイル名, &[報告の指定])?;
    let (ポストあり対照, 対照の標準出力) = 円盤の条件で撮る(出力先, moment::太陽円盤対照のファイル名, &[報告の指定, 円盤を消す指定])?;
    let (ポスト無し, _) = 円盤の条件で撮る(出力先, "sun_disk_no_post", &[ポストを外す指定])?;
    let (ポスト無し対照, _) = 円盤の条件で撮る(出力先, "sun_disk_no_post_control", &[ポストを外す指定, 円盤を消す指定])?;
    let マスク = 描画する(
        出力先,
        "sun_disk_region_mask",
        &条件::領域マスク {
            カメラ方位度: moment::太陽円盤のカメラ方位度,
        },
    )?;
    Ok(円盤の対 {
        ポストあり,
        ポストあり対照,
        ポスト無し,
        ポスト無し対照,
        領域区分: 領域区分::作る(&マスク)?,
        標準出力,
        対照の標準出力,
    })
}

/// 4枚すべてを同じ時刻・同じカメラ方位で撮る。1つでも動かすと、円盤以外の画素が対で決定的に一致しなくなる。
fn 円盤の条件で撮る(出力先: &Path, 出力名: &str, 追加引数: &[&str]) -> Result<(実行結果, String), String> {
    描画して標準出力も得る(
        出力先,
        出力名,
        &条件::時刻の絵 {
            一日内秒: moment::太陽円盤の一日内秒,
            カメラ方位度: moment::太陽円盤のカメラ方位度,
        },
        追加引数,
    )
}
