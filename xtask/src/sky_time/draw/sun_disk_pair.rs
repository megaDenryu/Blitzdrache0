//! 太陽円盤の明るさだけを変えた対の撮影。担当するのは「同じ時刻・同じカメラで円盤ありと円盤なしの絵を
//! ポスト処理ありと無しで1組ずつ撮り、その構図の領域区分も作る」ことである。受け取るのは実行環境、
//! 返すのは判定が読む4枚と領域区分と、ポストありの組の2つの報告である。
//!
//! ポスト処理を外した組を別に撮るのは、ポスト処理の光のにじみが円盤の明るさを画面の広い範囲へ数階調ぶん運び、
//! 地形の画素までバイトを動かすためである。にじみは間接照明の経路を通らないため、これを含めたまま
//! 「円盤の明るさが間接照明へ入っていない」ことを画素で言うことはできない。
//!
//! ポストありの組を絵と報告の対のまま持つのは、遠方環境の鍵と焼き直しの判断が対で同じであることを
//! 行の一致で確かめるためである。絵と報告を別々に持つと、別の実行の絵と報告を突き合わせる呼び方が書ける。

use super::super::moment;
use super::super::region::領域区分;
use super::super::run::条件;
use super::{描いて報告も得る, 描く};
use crate::acceptance::{描画検収の実行環境, 検収の1回の実行, 検収エラー, 終了時報告, 読み戻し画像};

/// 円盤の明るさだけが違う対と、その構図の領域区分。
pub(in crate::sky_time) struct 円盤の対 {
    ポストありの実行: 検収の1回の実行,
    ポストあり対照の実行: 検収の1回の実行,
    /// ポスト処理を外した円盤ありの絵。地形の表面画素のバイト一致をこの組で見る。
    pub(in crate::sky_time) ポスト無し: 読み戻し画像,
    pub(in crate::sky_time) ポスト無し対照: 読み戻し画像,
    /// この構図で、どの画素が空でどの画素が地形かの区分。
    pub(in crate::sky_time) 領域区分: 領域区分,
}

impl 円盤の対 {
    pub(in crate::sky_time) fn ポストあり(&self) -> &読み戻し画像 {
        self.ポストありの実行.画像()
    }

    pub(in crate::sky_time) fn ポストあり対照(&self) -> &読み戻し画像 {
        self.ポストあり対照の実行.画像()
    }

    pub(in crate::sky_time) fn 報告(&self) -> &終了時報告 {
        self.ポストありの実行.報告()
    }

    pub(in crate::sky_time) fn 対照の報告(&self) -> &終了時報告 {
        self.ポストあり対照の実行.報告()
    }
}

/// 遠方環境の鍵と焼き直しの判断を報告させる指定。ポストありの組だけに足すのは、対の間で行を比べるのに
/// 1組あれば足りるためである。
const 報告の指定: &str = "--report-atmosphere-passes";
/// 太陽円盤の放射輝度だけを0へ差し替える指定。カメラも時刻も動かさない。
const 円盤を消す指定: &str = "--sun-disk-off";
/// ポスト処理を外す指定。
const ポストを外す指定: &str = "--no-post";

pub(in crate::sky_time) fn 撮る(実行環境: &描画検収の実行環境) -> Result<円盤の対, 検収エラー> {
    let ポストありの実行 = 円盤の条件で撮る(実行環境, moment::太陽円盤のファイル名, &[報告の指定])?;
    let ポストあり対照の実行 = 円盤の条件で撮る(実行環境, moment::太陽円盤対照のファイル名, &[報告の指定, 円盤を消す指定])?;
    let ポスト無し = 円盤の条件で撮る(実行環境, "sun_disk_no_post", &[ポストを外す指定])?.画像を取り出す();
    let ポスト無し対照 = 円盤の条件で撮る(実行環境, "sun_disk_no_post_control", &[ポストを外す指定, 円盤を消す指定])?.画像を取り出す();
    let マスク = 描く(
        実行環境,
        "sun_disk_region_mask",
        &条件::領域マスク {
            カメラ方位度: moment::太陽円盤のカメラ方位度,
        },
        &[],
    )?;
    Ok(円盤の対 {
        ポストありの実行,
        ポストあり対照の実行,
        ポスト無し,
        ポスト無し対照,
        領域区分: 領域区分::作る(&マスク)?,
    })
}

/// 4枚すべてを同じ時刻・同じカメラ方位で撮る。1つでも動かすと、円盤以外の画素が対で決定的に一致しなくなる。
fn 円盤の条件で撮る(
    実行環境: &描画検収の実行環境,
    実行名の綴り: &str,
    追加の選択肢: &[&str],
) -> Result<検収の1回の実行, 検収エラー> {
    描いて報告も得る(
        実行環境,
        実行名の綴り,
        &条件::時刻の絵 {
            一日内秒: moment::太陽円盤の一日内秒,
            カメラ方位度: moment::太陽円盤のカメラ方位度,
        },
        追加の選択肢,
    )
}
