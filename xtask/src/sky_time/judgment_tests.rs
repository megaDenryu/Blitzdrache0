//! 阻害2是正の検査。隣接時刻だけを比べる`時刻間の変化を判定する`(旧実装)が夜明けと夕方の食い違いを
//! 見逃すことと、新設の`夜明けと夕方の対称性を判定する`が同じデータで落ちることを固定する。
//! 夜明けと夕方の空平均色を1階調だけ動かし、他の全区間の隣接差はしきい値を十分上回る値にしてある。

use super::judgment::{夜明けと夕方の対称性を判定する, 時刻間の変化を判定する};
use super::stats::領域別実測;

fn 実測を作る(空平均色: [u16; 3], 明部p95: u16, 暗部画素数: u64) -> 領域別実測 {
    領域別実測 {
        空平均色,
        空の飽和画素数: 0,
        明部p95,
        明部p99: 明部p95,
        暗部画素数,
        黒つぶれ画素数: 0,
    }
}

/// 夜明け(140,117,111)と夕方(141,118,112)を1階調だけ違えた4時刻。隣り合う区間の差はどれもしきい値を
/// 大きく上回るため、隣接差だけを見る判定は全区間を通す。
fn 対称性が崩れた4時刻を作る() -> Vec<領域別実測> {
    vec![
        実測を作る([140, 117, 111], 46, 500_000),
        実測を作る([203, 222, 232], 227, 50_000),
        実測を作る([141, 118, 112], 80, 470_000),
        実測を作る([9, 9, 21], 26, 519_000),
    ]
}

#[test]
fn 隣接差の判定は夜明けと夕方の1階調の食い違いを見逃す() {
    let 実測一覧 = 対称性が崩れた4時刻を作る();
    let 名前一覧 = ["夜明け", "正午", "夕方", "夜"];
    assert!(時刻間の変化を判定する(&名前一覧, &実測一覧, 600_000).is_ok());
}

#[test]
fn 対称性判定は同じデータで落ちる() {
    let 実測一覧 = 対称性が崩れた4時刻を作る();
    assert!(夜明けと夕方の対称性を判定する(&実測一覧).is_err());
}

#[test]
fn 対称性判定は一致するデータで通る() {
    let mut 実測一覧 = 対称性が崩れた4時刻を作る();
    実測一覧[2].空平均色 = 実測一覧[0].空平均色;
    assert!(夜明けと夕方の対称性を判定する(&実測一覧).is_ok());
}
