//! 太陽円盤ありと対照の画素位置ごとの差分を求める工程。受け取るのは同一構図の2枚、返すのは差分画素数と
//! その外接矩形である。対照はカメラを動かさず起動指定`--sun-disk-off`だけで撮るため、円盤以外の画素は
//! 決定的に一致するはずであり、差分は円盤とその周りのブルームだけに残る。円盤と無関係な画素が紛れ込むと
//! 差分の集合が離れた場所に散らばり、外接矩形が不釣り合いに広がることで見分けられる。
//!
//! 完全一致(閾値0)では差分を取らない。放射輝度8.0の円盤をブルームが画面の広い範囲へ数階調だけ滲ませるため、
//! 完全一致で比べると円盤と無関係な画素まで大量に拾ってしまう(2026-07-30の実測: 閾値0で537画素、
//! 外接矩形211x244)。3成分のうち最大の差が`差分とみなす閾値`を超える画素だけを数えると、実測は32から39画素の
//! 距離区分で安定し外接矩形も6x8前後に収まる(同じ実測で閾値1から6までのどれを取っても同じ帯に入ることを確かめた)。

use super::run::実行結果;

/// 3成分のうちどれか1つの差がこの値を超えたら「差分」とみなす。0(完全一致)ではブルームの
/// 遠く広い滲みまで拾ってしまうため使わない。1から6のどこでも実測は同じ帯に収まる(モジュール冒頭参照)。
const 差分とみなす閾値: u8 = 4;

pub(super) struct 円盤差分 {
    pub(super) 差分画素数: u64,
    /// 差分画素の外接矩形の横幅。差分が1つも無ければ0。
    pub(super) 外接矩形の幅: usize,
    /// 差分画素の外接矩形の縦幅。差分が1つも無ければ0。
    pub(super) 外接矩形の高さ: usize,
}

pub(super) fn 求める(円盤あり: &実行結果, 対照: &実行結果) -> Result<円盤差分, String> {
    if 円盤あり.幅 != 対照.幅 || 円盤あり.高さ != 対照.高さ {
        return Err(format!(
            "円盤ありと対照の寸法が違う({}x{}対{}x{})。同じカメラで撮れていない",
            円盤あり.幅, 円盤あり.高さ, 対照.幅, 対照.高さ
        ));
    }
    let mut 差分画素数 = 0_u64;
    let (mut 最小行, mut 最大行, mut 最小列, mut 最大列) = (usize::MAX, 0_usize, usize::MAX, 0_usize);
    for 添字 in 0..円盤あり.画素数() {
        if !画素が差分か(円盤あり.画素(添字), 対照.画素(添字)) {
            continue;
        }
        差分画素数 += 1;
        let 行 = 添字 / 円盤あり.幅;
        let 列 = 添字 % 円盤あり.幅;
        最小行 = 最小行.min(行);
        最大行 = 最大行.max(行);
        最小列 = 最小列.min(列);
        最大列 = 最大列.max(列);
    }
    if 差分画素数 == 0 {
        return Ok(円盤差分 {
            差分画素数: 0,
            外接矩形の幅: 0,
            外接矩形の高さ: 0,
        });
    }
    Ok(円盤差分 {
        差分画素数,
        外接矩形の幅: 最大列 - 最小列 + 1,
        外接矩形の高さ: 最大行 - 最小行 + 1,
    })
}

fn 画素が差分か(左: [u8; 3], 右: [u8; 3]) -> bool {
    左.iter().zip(右).any(|(左, 右)| 左.abs_diff(右) > 差分とみなす閾値)
}
