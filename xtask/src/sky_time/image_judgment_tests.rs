//! 阻害1是正の検査。画面全体の高輝度画素数を単独の上下限(下限1・上限2000。削除済みの
//! `円盤画素数の上限`と同じ値)だけで見る旧実装は、円盤の位置を1度も見ないため、円盤が消えて
//! 円盤と無関係な1画素だけが飽和する退行を通してしまう。対照との差分を取る新実装が
//! 同じデータで落ちることと、健全な円盤の絵は通すことを固定する。

use super::draw::絵の束;
use super::image_judgment::太陽円盤を判定する;
use super::run::実行結果;
use super::stats::明るさ下限以上の画素数;

const 幅: usize = 8;
const 高さ: usize = 8;

fn 一様な絵を作る(明るさ: u8) -> Vec<u8> {
    [明るさ, 明るさ, 明るさ, 255].repeat(幅 * 高さ)
}

fn 先頭n画素だけ飽和させた絵を作る(件数: usize) -> Vec<u8> {
    let mut rgba8 = 一様な絵を作る(10);
    for 添字 in 0..件数 {
        rgba8[添字 * 4] = 255;
        rgba8[添字 * 4 + 1] = 255;
        rgba8[添字 * 4 + 2] = 255;
    }
    rgba8
}

fn 束を作る(太陽円盤: Vec<u8>, 太陽円盤対照: Vec<u8>) -> 絵の束 {
    絵の束 {
        時刻ごと: Vec::new(),
        再描画: 実行結果::テスト用に作る(幅, 高さ, 一様な絵を作る(10)),
        太陽円盤: 実行結果::テスト用に作る(幅, 高さ, 太陽円盤),
        太陽円盤対照: 実行結果::テスト用に作る(幅, 高さ, 太陽円盤対照),
    }
}

#[test]
fn 旧実装の上下限は円盤が消えても通ってしまう() {
    let 太陽円盤 = 実行結果::テスト用に作る(幅, 高さ, 先頭n画素だけ飽和させた絵を作る(1));
    let 画素数 = 明るさ下限以上の画素数(&太陽円盤, 250);
    assert!((1..=2000).contains(&画素数), "旧実装が合格と判定していた画素数のはずが{画素数}だった");
}

#[test]
fn 新実装は円盤と対照が同じ飽和画素を持つ退行を落とす() {
    let 束 = 束を作る(先頭n画素だけ飽和させた絵を作る(1), 先頭n画素だけ飽和させた絵を作る(1));
    assert!(太陽円盤を判定する(&束).is_err());
}

#[test]
fn 新実装は対照に円盤が無く差分が見込み帯に入る絵を通す() {
    let 束 = 束を作る(先頭n画素だけ飽和させた絵を作る(20), 一様な絵を作る(10));
    assert!(太陽円盤を判定する(&束).is_ok());
}

#[test]
fn 新実装は対照自体が汚れていれば落ちる() {
    let 束 = 束を作る(先頭n画素だけ飽和させた絵を作る(20), 先頭n画素だけ飽和させた絵を作る(10));
    assert!(太陽円盤を判定する(&束).is_err());
}
