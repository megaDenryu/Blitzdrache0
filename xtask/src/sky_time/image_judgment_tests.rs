//! 対照撮影の画素位置ごとの差分判定を固定する検査。円盤なりの形をした差分は通し、円盤が消えて差分が
//! 0になる退行と、円盤あり側だけに円盤と無関係な離れた画素が混じる退行の両方を落とすことを確かめる。
//! 旧実装(画面全体の高輝度画素数を単独の上下限だけで見る形)は円盤の位置を1度も見ないため、
//! 後者の退行を通してしまっていた。

use super::image_judgment::太陽円盤を判定する;
use crate::acceptance::読み戻し画像;

const 幅: usize = 16;
const 高さ: usize = 16;

fn 一様な絵を作る(明るさ: u8) -> Vec<u8> {
    [明るさ, 明るさ, 明るさ, 255].repeat(幅 * 高さ)
}

fn 位置一覧を飽和させた絵を作る(位置一覧: &[(usize, usize)]) -> Vec<u8> {
    let mut rgba8 = 一様な絵を作る(10);
    for &(行, 列) in 位置一覧 {
        let 添字 = (行 * 幅 + 列) * 4;
        rgba8[添字] = 255;
        rgba8[添字 + 1] = 255;
        rgba8[添字 + 2] = 255;
    }
    rgba8
}

/// 円盤に見立てた3x3の塊(9画素)。見込み帯の下限8を満たし、外接矩形(3x3=9)が画素数と釣り合う。
fn 円盤の形の位置一覧() -> Vec<(usize, usize)> {
    (6..9).flat_map(|行| (6..9).map(move |列| (行, 列))).collect()
}

fn 対を作る(円盤あり: Vec<u8>, 対照: Vec<u8>) -> (読み戻し画像, 読み戻し画像) {
    (
        読み戻し画像::テスト用に作る(幅, 高さ, 円盤あり),
        読み戻し画像::テスト用に作る(幅, 高さ, 対照),
    )
}

#[test]
fn 新実装は円盤の形をした差分を通す() {
    let (円盤あり, 対照) = 対を作る(位置一覧を飽和させた絵を作る(&円盤の形の位置一覧()), 一様な絵を作る(10));
    assert!(太陽円盤を判定する(&円盤あり, &対照).is_ok());
}

#[test]
fn 新実装は円盤が消えて両者が同じ絵になる退行を落とす() {
    let 絵 = 位置一覧を飽和させた絵を作る(&円盤の形の位置一覧());
    let (円盤あり, 対照) = 対を作る(絵.clone(), 絵);
    assert!(太陽円盤を判定する(&円盤あり, &対照).is_err());
}

#[test]
fn 新実装は円盤あり側だけに円盤と無関係な離れた飽和画素が混じると落ちる() {
    let mut 位置一覧 = 円盤の形の位置一覧();
    位置一覧.push((0, 0));
    位置一覧.push((15, 15));
    let (円盤あり, 対照) = 対を作る(位置一覧を飽和させた絵を作る(&位置一覧), 一様な絵を作る(10));
    assert!(太陽円盤を判定する(&円盤あり, &対照).is_err());
}
