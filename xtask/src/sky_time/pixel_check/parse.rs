//! `blitz_app`が出す「空代表画素」の行を読む工程。受け取るのは終了時報告、返すのは行ごとの構造である。
//! 書式は`crates/blitz_app/src/reports/sky_pixel/row.rs`とこの工程の間の契約であり、`atmosphere_lut/parse`と
//! 同じ「鍵=値」の語を空白で切る書式に揃えてある。

use crate::acceptance::{報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

const 行の見出し: 報告の見出し = 報告の見出し::定数から生成する("空代表画素 ");
/// この報告の行は全項目が「鍵=値」の形で並ぶ。
const 値の結ばれ方: 鍵に値が結ばれる形 = 鍵に値が結ばれる形::等号の後ろが値である;

pub(super) struct 代表画素行 {
    pub(super) 横: u32,
    pub(super) 縦: u32,
    pub(super) 期待: [f64; 3],
    pub(super) 実測: [f64; 3],
}

pub(super) fn 読み取る(報告: &終了時報告) -> Result<Vec<代表画素行>, 検収エラー> {
    let mut 一覧 = Vec::new();
    for 行 in 報告.見出しで始まる行の一覧(&行の見出し) {
        一覧.push(一行を読む(&行)?);
    }
    Ok(一覧)
}

fn 一行を読む(行: &報告の行) -> Result<代表画素行, 検収エラー> {
    Ok(代表画素行 {
        横: 添字を読む(行, "横")?,
        縦: 添字を読む(行, "縦")?,
        期待: [実数を読む(行, "期待赤")?, 実数を読む(行, "期待緑")?, 実数を読む(行, "期待青")?],
        実測: [実数を読む(行, "実測赤")?, 実数を読む(行, "実測緑")?, 実数を読む(行, "実測青")?],
    })
}

fn 添字を読む(行: &報告の行, 鍵: &'static str) -> Result<u32, 検収エラー> {
    行.鍵に結ばれた数(&報告の行の鍵::定数から生成する(鍵), 値の結ばれ方)
}

fn 実数を読む(行: &報告の行, 鍵: &'static str) -> Result<f64, 検収エラー> {
    行.鍵に結ばれた数(&報告の行の鍵::定数から生成する(鍵), 値の結ばれ方)
}
