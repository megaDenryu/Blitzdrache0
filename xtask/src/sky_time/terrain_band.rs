//! 地形の破綻防止帯の判定。受け取るのは時刻ごとの実測とジオメトリ領域の画素数、返すのは報告へ載せる要約である。
//!
//! 地形の間接照明が定数近似から天空の遠方環境へ替わり、地表の明るさが時刻とともに動くようになった。この段では
//! 自動露出を入れない(正本どおり順3-IIb)ため、機械条件は破綻の有無だけを見る広い帯にし、明るさの自然さは
//! オーナーの目視へ残す(参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Icの消費式と実装段割り」の露出の段落)。
//!
//! 帯の閾値と割合の上限は`xtask/src/damage_band.rs`が持つ台帳から引く。同じ「間接照明で絵が壊れていないか」を
//! 見る帯であり、世界が違うだけで判定の意味が変わらないため、帯ごとに別の値を持たない。
//!
//! 注意: RGBA8の読み戻しからは非有限値をそのまま観測できない。明るさの圧縮とsRGB符号化を通った後の値が帯に
//! 収まることを、有限性の観測できる代理として置く(`judgment::夜を判定する`と同じ扱い)。

use super::stats::領域別実測;
use crate::acceptance::{判定の名前, 判定の破れ};
use crate::damage_band::{割合にする, 飽和割合の上限, 黒潰れ割合の上限};

const 破綻防止帯の判定領域の画素: 判定の名前 = 判定の名前::定数から生成する("破綻防止帯の判定領域の画素");

pub(super) fn 破綻防止帯を判定する(
    名前一覧: &[&str], 実測一覧: &[領域別実測], 幾何画素数: u64
) -> Result<String, 判定の破れ> {
    if 幾何画素数 == 0 {
        return Err(破綻防止帯の判定領域の画素.あるはずのものが無い破れ());
    }
    let mut 行一覧 = Vec::new();
    for (名前, 実測) in 名前一覧.iter().zip(実測一覧) {
        let 黒潰れ割合 = 割合にする(実測.地形の黒潰れ画素数, 幾何画素数);
        let 飽和割合 = 割合にする(実測.地形の飽和画素数, 幾何画素数);
        地形の割合の判定名(名前, "黒潰れ").上限を課す(黒潰れ割合, 黒潰れ割合の上限)?;
        地形の割合の判定名(名前, "飽和").上限を課す(飽和割合, 飽和割合の上限)?;
        行一覧.push(format!("{名前}は黒潰れ{黒潰れ割合:.4}・飽和{飽和割合:.4}"));
    }
    Ok(format!("地形{幾何画素数}画素の破綻防止帯は{}", 行一覧.join("、")))
}

fn 地形の割合の判定名(時刻の名前: &str, 破れ方: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{時刻の名前}の地形の{破れ方}画素の割合"))
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    fn 実測(黒潰れ: u64, 飽和: u64) -> 領域別実測 {
        領域別実測 {
            空平均色: [0; 3],
            空の飽和画素数: 0,
            明部p95: 0,
            明部p99: 0,
            暗部画素数: 0,
            黒つぶれ画素数: 0,
            地形の黒潰れ画素数: 黒潰れ,
            地形の飽和画素数: 飽和,
        }
    }

    #[test]
    fn 帯に収まれば要約を返す() {
        assert!(破綻防止帯を判定する(&["正午"], &[実測(100, 100)], 10000).is_ok());
    }

    #[test]
    fn 黒潰れが上限を超えたら失敗にする() {
        assert!(破綻防止帯を判定する(&["夜"], &[実測(2001, 0)], 10000).is_err());
    }

    #[test]
    fn 飽和が上限を超えたら失敗にする() {
        assert!(破綻防止帯を判定する(&["正午"], &[実測(0, 201)], 10000).is_err());
    }
}
