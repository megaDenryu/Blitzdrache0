//! 円盤の対で1文字も違ってはならない報告の行の契約。担当するのは、どの行が対で一致すべきかの一覧と、
//! その一致の確認だけであり、画素の判定は親モジュールが持つ。
//!
//! 行の契約をここが所有するのは、太陽円盤の明るさが焼き上げの入力に現れない構造であることを、
//! この2行の一致が代表して示すためである。どの行を見るかが判定の本文へ散ると、
//! 見る行を1つ落としても判定が緑のまま通る。

use super::super::draw::sun_disk_pair::円盤の対;

/// 対で一致していなければならない報告の行の先頭。鍵の行は焼き上げの即時定数をすべて含み、パス数の行は
/// その鍵に対して実際に積んだ本数を持つ。
const 一致を求める行の先頭: [&str; 2] = ["遠方環境の鍵 ", "間接照明生成パス数 "];

pub(super) fn 行の一致を確かめる(対: &円盤の対) -> Result<(), String> {
    for 先頭 in 一致を求める行の先頭 {
        let 円盤あり = 行を探す(&対.標準出力, 先頭, "円盤あり")?;
        let 対照 = 行を探す(&対.対照の標準出力, 先頭, "円盤なし")?;
        if 円盤あり != 対照 {
            return Err(format!("円盤ありと円盤なしで行が違う: 円盤あり[{円盤あり}] 円盤なし[{対照}]"));
        }
    }
    Ok(())
}

fn 行を探す<'出力>(標準出力: &'出力 str, 先頭: &str, 側の名前: &str) -> Result<&'出力 str, String> {
    標準出力
        .lines()
        .find(|行| 行.starts_with(先頭))
        .ok_or_else(|| format!("{側の名前}の出力に{}で始まる行が無い", 先頭.trim_end()))
}
