//! 円盤の対で1文字も違ってはならない報告の行の契約。担当するのは、どの行が対で一致すべきかの一覧と、
//! その一致の確認だけであり、画素の判定は親モジュールが持つ。
//!
//! 行の契約をここが所有するのは、太陽円盤の明るさが焼き上げの入力に現れない構造であることを、
//! この2行の一致が代表して示すためである。どの行を見るかが判定の本文へ散ると、
//! 見る行を1つ落としても判定が緑のまま通る。

use super::super::draw::sun_disk_pair::円盤の対;
use crate::acceptance::{判定の名前, 検収エラー};
use crate::report_heading::報告の見出し;

/// 対で一致していなければならない報告の行の見出し。鍵の行は焼き上げの即時定数をすべて含み、パス数の行は
/// その鍵に対して実際に積んだ本数を持つ。
const 一致を求める行の見出し: [報告の見出し; 2] = [
    報告の見出し::定数から生成する("遠方環境の鍵 "),
    報告の見出し::定数から生成する("間接照明生成パス数 "),
];

pub(super) fn 行の一致を確かめる(対: &円盤の対) -> Result<(), 検収エラー> {
    for 見出し in &一致を求める行の見出し {
        let 円盤あり = 対.報告().見出しの1行(見出し)?;
        let 円盤なし = 対.対照の報告().見出しの1行(見出し)?;
        行の判定名(見出し).綴りの一致を課す(円盤なし.原文(), 円盤あり.原文())?;
    }
    Ok(())
}

fn 行の判定名(見出し: &報告の見出し) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("円盤なしの報告の「{見出し}」の行(円盤ありと1文字も違ってはならない)"))
}
