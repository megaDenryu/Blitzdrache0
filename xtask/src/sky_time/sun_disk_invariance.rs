//! 太陽円盤の明るさが動かさないものを判定する工程。受け取るのは円盤の対、返すのは報告へ載せる要約である。
//!
//! 2つを要求する。遠方環境の鍵と焼き直しの判断が対で1文字も違わないこと、ポスト処理を外した対で地形の表面画素が
//! バイト一致することである。円盤そのものがこの構図に写っていることは`image_judgment::太陽円盤を判定する`が
//! ポスト処理ありの対で確かめているため、ここでは負の対照を別に置かない。
//!
//! 地形の表面画素のバイト一致が、焼いた立方体画像の中身の一致まで含む。拡散照度は立方体画像の全テクセルを
//! 畳み込んだ値であり、1テクセルでも違えば地形の表面へ出るためである。本番のフレーム経路へ立方体画像の
//! 読み戻し口を足さないのはこのためである(参照: `_doc/設計/放射輝度問い合わせ階層.md`「3-Ic-3bの実装」)。
//!
//! ポスト処理を外した対で見るのは、ポスト処理の光のにじみが円盤の明るさを画面の広い範囲へ数階調ぶん運び、
//! 地形の画素までバイトを動かすためである。にじみは間接照明の経路を通らないため、これを含めたまま
//! 「円盤の明るさが間接照明へ入っていない」ことを画素で言うことはできない。
//!
//! 注意: ポスト処理を外すと明るさの圧縮が掛からず、太陽の周りの空は放射輝度1.0で頭打ちになって白へ張り付く
//! (2026-08-04の実測で空409572画素のうち120022画素)。この対で空の画素を見ても円盤の有無は分からない。
//! 地形の画素は張り付いていないことを`中間調の割合`が確かめ、バイト一致が中身なしで成り立つことを防ぐ。

use super::draw::sun_disk_pair::円盤の対;
use super::region::区分;

/// 対で一致していなければならない報告の行の先頭。鍵の行は焼き上げの即時定数をすべて含み、パス数の行は
/// その鍵に対して実際に積んだ本数を持つ。
const 一致を求める行の先頭: [&str; 2] = ["遠方環境の鍵 ", "間接照明生成パス数 "];

/// 地形の画素のうち、飽和にも黒潰れにも張り付いていない画素に求める割合の下限。
const 中間調の割合の下限: f64 = 0.5;
/// 飽和とみなす下限と黒潰れとみなす上限。破綻防止帯と同じ値である。
const 飽和の下限: u8 = 254;
const 黒潰れの上限: u8 = 2;

pub(super) fn 円盤が動かさないものを判定する(対: &円盤の対) -> Result<String, String> {
    行の一致を確かめる(対)?;
    対.領域区分.寸法が合うか(&対.ポスト無し)?;
    対.領域区分.寸法が合うか(&対.ポスト無し対照)?;
    let 地形の差分 = 地形の画素を数える(対, 差分か);
    if 地形の差分 != 0 {
        return Err(format!(
            "ポスト処理を外した対で地形の表面画素が{地形の差分}個食い違った。太陽円盤の明るさが間接照明の経路へ入っている"
        ));
    }
    let 中間調 = 地形の画素を数える(対, |画素, _| 中間調か(画素));
    let 割合 = 割合にする(中間調, 対.領域区分.幾何画素数);
    if 割合 < 中間調の割合の下限 {
        return Err(format!(
            "ポスト処理を外した地形の中間調画素が{割合:.4}しかなく、下限{中間調の割合の下限}に満たない。バイト一致が張り付いた値どうしの一致になっている"
        ));
    }
    Ok(format!(
        "遠方環境の鍵と積んだ本数の行が対で一致し、ポスト処理を外した対で地形{}画素がバイト一致した(中間調の割合{割合:.4})",
        対.領域区分.幾何画素数
    ))
}

fn 行の一致を確かめる(対: &円盤の対) -> Result<(), String> {
    for 先頭 in 一致を求める行の先頭 {
        let 円盤あり = 行を探す(&対.標準出力, 先頭, "円盤あり")?;
        let 対照 = 行を探す(&対.対照の標準出力, 先頭, "円盤なし")?;
        if 円盤あり != 対照 {
            return Err(format!("円盤ありと円盤なしで行が違う: 円盤あり[{円盤あり}] 円盤なし[{対照}]"));
        }
    }
    Ok(())
}

/// 地形の画素のうち、与えた条件を満たすものを数える。条件は円盤ありと対照の画素を受け取る。
fn 地形の画素を数える(対: &円盤の対, 条件: impl Fn([u8; 3], [u8; 3]) -> bool) -> u64 {
    (0..対.ポスト無し.画素数())
        .filter(|添字| 対.領域区分.区分(*添字) == 区分::ジオメトリ)
        .filter(|添字| 条件(対.ポスト無し.画素(*添字), 対.ポスト無し対照.画素(*添字)))
        .count()
        .try_into()
        .unwrap_or(u64::MAX)
}

fn 差分か(円盤あり: [u8; 3], 対照: [u8; 3]) -> bool {
    円盤あり != 対照
}

fn 中間調か(画素: [u8; 3]) -> bool {
    !画素.iter().all(|成分| *成分 >= 飽和の下限) && !画素.iter().all(|成分| *成分 <= 黒潰れの上限)
}

fn 割合にする(件数: u64, 画素数: u64) -> f64 {
    if 画素数 == 0 {
        return 0.0;
    }
    f64::from(u32::try_from(件数).unwrap_or(u32::MAX)) / f64::from(u32::try_from(画素数).unwrap_or(u32::MAX))
}

fn 行を探す<'出力>(標準出力: &'出力 str, 先頭: &str, 側の名前: &str) -> Result<&'出力 str, String> {
    標準出力
        .lines()
        .find(|行| 行.starts_with(先頭))
        .ok_or_else(|| format!("{側の名前}の出力に{}で始まる行が無い", 先頭.trim_end()))
}
