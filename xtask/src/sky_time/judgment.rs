//! 領域別の実測値を判定する工程。受け取るのは時刻順に並んだ実測値、返すのは合否である。
//!
//! 「変化している」ことを見る判定は隣り合う時刻の間だけで比べる。夜明けと夕方は太陽高度がどちらも
//! ちょうど0で方位が東西に反対であり、北を向いた構図では互いの鏡像に近い。この2つを直接比べて変化量を
//! 求める判定は、絵が変わることでなく構図の対称性を測ってしまう。一方、夜明けと夕方の空平均色が
//! 完全に一致するという対称性そのものは、`夜明けと夕方の対称性を判定する`が添字0と添字2を直接比べて見る。

use super::moment;
use super::stats::領域別実測;

/// 隣り合う時刻の間で空の平均色に求める変化量。3成分の差の合計で測る。
const 空色の変化下限: i32 = 20;
/// 隣り合う時刻の間で明部のp95に求める変化量。
const 明部の変化下限: i32 = 20;
/// 隣り合う時刻の間で暗部の画素数に求める変化量。ジオメトリ領域に対する百分率で測る。
const 暗部の変化下限百分率: u64 = 5;
/// 夜の地表が収まる明るさの帯。環境光0.005に露出2段(4倍)を掛けてACESとsRGB符号化を通した値が26であり、
/// その前後の幅を取る。この帯を上に外れたときは方向光の寄与が夜に残っている。
const 夜の明部下限: u16 = 18;
const 夜の明部上限: u16 = 34;
/// 夜の明るさの99パーセンタイルに許す上限。世界の点光源は時刻から導かないため、原点近くに小さな明部が残る。
const 夜の九九分位上限: u16 = 40;

pub(super) fn 時刻間の変化を判定する(名前一覧: &[&str], 実測一覧: &[領域別実測], 幾何画素数: u64) -> Result<(), String> {
    let 暗部下限 = 幾何画素数 * 暗部の変化下限百分率 / 100;
    for (添字, 対) in 実測一覧.windows(2).enumerate() {
        let (前, 後) = (&対[0], &対[1]);
        let 区間 = format!("{}と{}", 名前一覧[添字], 名前一覧[添字 + 1]);
        let 空色差 = 色差を求める(前.空平均色, 後.空平均色);
        if 空色差 < 空色の変化下限 {
            return Err(format!("{区間}の空の平均色の差が{空色差}で、下限{空色の変化下限}に満たない"));
        }
        let 明部差 = i32::from(前.明部p95).abs_diff(i32::from(後.明部p95));
        if i32::try_from(明部差).unwrap_or(i32::MAX) < 明部の変化下限 {
            return Err(format!("{区間}の明部p95の差が{明部差}で、下限{明部の変化下限}に満たない"));
        }
        let 暗部差 = 前.暗部画素数.abs_diff(後.暗部画素数);
        if 暗部差 < 暗部下限 {
            return Err(format!("{区間}の暗部の画素数の差が{暗部差}で、下限{暗部下限}に満たない"));
        }
    }
    Ok(())
}

/// 夜だけに課す判定。方向光の寄与が0近傍であること、空も地表も0へ落ちていないことを確かめる。
///
/// 注意: RGBA8の読み戻しからは非有限値をそのまま観測できない。トーンマップとsRGB符号化を通った後の値が
/// 期待した帯に収まることを、有限性の観測できる代理として置く。天空状態そのものの有限性は`sky-state`が確かめる。
pub(super) fn 夜を判定する(実測: &領域別実測) -> Result<(), String> {
    if !(夜の明部下限..=夜の明部上限).contains(&実測.明部p95) {
        return Err(format!(
            "夜の明部p95が{}で、環境光だけの期待帯{夜の明部下限}から{夜の明部上限}に収まらない",
            実測.明部p95
        ));
    }
    if 実測.明部p99 > 夜の九九分位上限 {
        return Err(format!("夜の明部p99が{}で、上限{夜の九九分位上限}を超える", 実測.明部p99));
    }
    if 実測.黒つぶれ画素数 != 0 {
        return Err(format!("夜に3成分すべてが0の画素が{}個ある", 実測.黒つぶれ画素数));
    }
    Ok(())
}

fn 色差を求める(前: [u16; 3], 後: [u16; 3]) -> i32 {
    前.iter().zip(後).map(|(左, 右)| i32::from(左.abs_diff(右))).sum()
}

/// 夜明けと夕方の空平均色がバイト一致することを確かめる。太陽高度がどちらもちょうど0で方位だけ東西反対の
/// 対称な配置であるため、空の放射輝度は理論上同じ値になる。`時刻間の変化を判定する`は隣り合う時刻しか
/// 比べないため、添字0(夜明け)と添字2(夕方)を直接比べるこの判定が無いと、円盤や霞の混入で対称性が崩れる
/// 退行を隣接差の判定だけでは検出できない。
pub(super) fn 夜明けと夕方の対称性を判定する(実測一覧: &[領域別実測]) -> Result<(), String> {
    let 夜明け = &実測一覧[moment::夜明けの添字];
    let 夕方 = &実測一覧[moment::夕方の添字];
    if 夜明け.空平均色 != 夕方.空平均色 {
        return Err(format!(
            "夜明けの空平均色{:?}と夕方の空平均色{:?}がバイト一致しない(太陽高度0の対称性が破れている)",
            夜明け.空平均色, 夕方.空平均色
        ));
    }
    Ok(())
}

/// どの時刻の空も飽和していないことを確かめる。飽和は空描画方針の放射輝度倍率が大きすぎることを表し、
/// 太陽円盤を明るさだけで見分ける判定も同時に成立しなくなる。
pub(super) fn 空の飽和を判定する(名前一覧: &[&str], 実測一覧: &[領域別実測]) -> Result<(), String> {
    for (名前, 実測) in 名前一覧.iter().zip(実測一覧) {
        if 実測.空の飽和画素数 != 0 {
            return Err(format!("{名前}の空に飽和した画素が{}個ある", 実測.空の飽和画素数));
        }
    }
    Ok(())
}
