//! 領域別の実測値を判定する工程。受け取るのは時刻順に並んだ実測値、返すのは合否である。
//!
//! 「変化している」ことを見る判定は隣り合う時刻の間だけで比べる。夜明けと夕方は太陽高度がどちらも
//! ちょうど0で方位が東西に反対であり、北を向いた構図では互いの鏡像に近い。この2つを直接比べて変化量を
//! 求める判定は、絵が変わることでなく構図の対称性を測ってしまう。一方、夜明けと夕方の空平均色が
//! 完全に一致するという対称性そのものは、`夜明けと夕方の対称性を判定する`が添字0と添字2を直接比べて見る。
//!
//! 階調の差を実数へ写してから課すのは、差が符号を持つためである。写しに誤差は無く、比べの結果は変わらない。

use super::moment;
use super::stats::領域別実測;
use crate::acceptance::{判定の名前, 判定の破れ};

/// 隣り合う時刻の間で空の平均色に求める変化量。3成分の差の合計で測る。
const 空色の変化下限: i32 = 20;
/// 隣り合う時刻の間で明部のp95に求める変化量。
const 明部の変化下限: i32 = 20;
/// 隣り合う時刻の間で暗部の画素数に求める変化量。ジオメトリ領域に対する百分率で測る。
const 暗部の変化下限百分率: u64 = 5;
/// 夜の地表が収まる明るさの帯。地形の間接照明が定数近似から天空の遠方環境へ替わり、夜の地表を照らすのが
/// 環境光係数0.005でなく夜空放射輝度から焼いた拡散照度になったため、2026-08-04の実測は13である。
/// 帯はその前後におよそ5割の幅を取る。この帯を上に外れたときは方向光の寄与が夜に残っている(方向光が効く
/// 夕方の実測は130であり、上限20とは大きく離れている)。下に外れたときは間接照明が届いていない。
const 夜の明部下限: u16 = 8;
const 夜の明部上限: u16 = 20;
/// 夜の明るさの99パーセンタイルに許す上限。世界の点光源は時刻から導かないため、原点近くに小さな明部が残る。
/// 2026-08-04の実測は14であり、点光源の写り込み方が構図で動く余地を見て上限を24に取る。
const 夜の九九分位上限: u16 = 24;

const 夜の明部の九五分位: 判定の名前 =
    判定の名前::定数から生成する("夜のジオメトリ領域の明部の第95百分位(帯は環境光だけで照らされた明るさである)");
const 夜の明部の九九分位: 判定の名前 = 判定の名前::定数から生成する("夜のジオメトリ領域の明部の第99百分位");
const 夜の全成分が零の画素: 判定の名前 = 判定の名前::定数から生成する("夜の3成分すべてが0の画素");
const 夜明けと夕方の空平均色: 判定の名前 =
    判定の名前::定数から生成する("夜明けと夕方の空平均色(食い違えば太陽高度0の対称性が破れている)");

pub(super) fn 時刻間の変化を判定する(
    名前一覧: &[&str], 実測一覧: &[領域別実測], 幾何画素数: u64
) -> Result<(), 判定の破れ> {
    let 暗部下限 = 幾何画素数 * 暗部の変化下限百分率 / 100;
    for (添字, 対) in 実測一覧.windows(2).enumerate() {
        let (前, 後) = (&対[0], &対[1]);
        let 区間 = format!("{}と{}", 名前一覧[添字], 名前一覧[添字 + 1]);
        let 空色差 = 色差を求める(前.空平均色, 後.空平均色);
        区間の判定名(&区間, "空の平均色の差").下限を課す(f64::from(空色差), f64::from(空色の変化下限))?;
        let 明部差 = i32::from(前.明部の第95百分位).abs_diff(i32::from(後.明部の第95百分位));
        区間の判定名(&区間, "明部の第95百分位の差").下限を課す(f64::from(明部差), f64::from(明部の変化下限))?;
        let 暗部差 = 前.暗部画素数.abs_diff(後.暗部画素数);
        区間の判定名(&区間, "暗部の画素数の差").下限を課す(暗部差, 暗部下限)?;
    }
    Ok(())
}

/// 夜だけに課す判定。方向光の寄与が0近傍であること、空も地表も0へ落ちていないことを確かめる。
///
/// 注意: RGBA8の読み戻しからは非有限値をそのまま観測できない。明るさの圧縮とsRGB符号化を通った後の値が
/// 期待した帯に収まることを、有限性の観測できる代理として置く。天空状態そのものの有限性は`sky-state`が確かめる。
pub(super) fn 夜を判定する(実測: &領域別実測) -> Result<(), 判定の破れ> {
    夜の明部の九五分位.許容の範囲を課す(u32::from(実測.明部の第95百分位), u32::from(夜の明部下限), u32::from(夜の明部上限))?;
    夜の明部の九九分位.上限を課す(u32::from(実測.明部の第99百分位), u32::from(夜の九九分位上限))?;
    夜の全成分が零の画素.零件であることを課す(実測.黒つぶれ画素数)
}

fn 色差を求める(前: [u16; 3], 後: [u16; 3]) -> i32 {
    前.iter().zip(後).map(|(左, 右)| i32::from(左.abs_diff(右))).sum()
}

fn 区間の判定名(区間: &str, 量の名前: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{区間}の{量の名前}"))
}

/// 夜明けと夕方の空平均色がバイト一致することを確かめる。太陽高度がどちらもちょうど0で方位だけ東西反対の
/// 対称な配置であるため、空の放射輝度は理論上同じ値になる。`時刻間の変化を判定する`は隣り合う時刻しか
/// 比べないため、添字0(夜明け)と添字2(夕方)を直接比べるこの判定が無いと、円盤や霞の混入で対称性が崩れる
/// 退行を隣接差の判定だけでは検出できない。
pub(super) fn 夜明けと夕方の対称性を判定する(実測一覧: &[領域別実測]) -> Result<(), 判定の破れ> {
    let 夜明け = &実測一覧[moment::夜明けの添字];
    let 夕方 = &実測一覧[moment::夕方の添字];
    夜明けと夕方の空平均色.綴りの一致を課す(&成分の綴り(夕方.空平均色), &成分の綴り(夜明け.空平均色))
}

fn 成分の綴り(色: [u16; 3]) -> String {
    format!("{色:?}")
}

/// どの時刻の空も飽和していないことを確かめる。飽和は空描画方針の放射輝度倍率が大きすぎることを表し、
/// 太陽円盤を明るさだけで見分ける判定も同時に成立しなくなる。
pub(super) fn 空の飽和を判定する(名前一覧: &[&str], 実測一覧: &[領域別実測]) -> Result<(), 判定の破れ> {
    for (名前, 実測) in 名前一覧.iter().zip(実測一覧) {
        空の飽和画素の判定名(名前).零件であることを課す(実測.空の飽和画素数)?;
    }
    Ok(())
}

fn 空の飽和画素の判定名(時刻の名前: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{時刻の名前}の空の飽和した画素"))
}
