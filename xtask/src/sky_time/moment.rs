//! 検収が描く代表時刻のうち、この入口だけが使う添字と太陽円盤の条件。時刻の表そのものは`crate::day_moment`が持つ。
//!
//! 夜明けと夕方はどちらも太陽高度がちょうど0であり、方位だけが東と西で反対になる。この2つは互いの鏡像に近いため、
//! 隣り合う時刻の間で変化を見る判定(`judgment::時刻間の変化を判定する`)とは別に、夜明けと夕方だけを直接比べる
//! 対称性の判定(`judgment::夜明けと夕方の対称性を判定する`)を`夜明けの添字`・`夕方の添字`で持つ。

pub(super) use crate::day_moment::代表時刻一覧;

/// 決定性を確かめるために2度描く時刻の添字。正午は空も地表も明るく、値の違いが最も出やすい。
pub(super) const 再描画する添字: usize = 1;

/// 夜明けの添字。夕方との対称性判定で使う。
pub(super) const 夜明けの添字: usize = 0;

/// 夕方の添字。夜明けとの対称性判定で使う。
pub(super) const 夕方の添字: usize = 2;

/// 夜の添字。夜だけに課す判定(方向光の寄与が0近傍であること)で使う。
pub(super) const 夜の添字: usize = 3;

/// 太陽円盤を画面へ入れる条件。17時(太陽高度約12度)を選ぶのは、大気のベイク済み画像方式が円盤の透過率を視線ごとに
/// 大気で減衰させるためである。太陽高度ちょうど0(夕方64800秒)では経路長が最大になり、代表テクセルの実測
/// (地表に近い視線で緑1パーセント台まで減光)と同じ桁まで円盤が暗んで飽和しない。方位度は緯度35度・太陽赤緯0度の
/// 球面天文学(`sun_position.rs`)から18時とは別に求め直した値である。
pub(super) const 太陽円盤のファイル名: &str = "sun_disk";
pub(super) const 太陽円盤の一日内秒: &str = "61200";
pub(super) const 太陽円盤のカメラ方位度: &str = "99";

/// 太陽円盤の対照を撮るファイル名。カメラは動かさず、`太陽円盤のカメラ方位度`と同じ方位・同じ一日内秒で撮る。
/// 起動指定`--sun-disk-off`が空描画方針の太陽円盤放射輝度だけを0へ上書きするため、円盤以外の地形・空・霞の
/// 画素は円盤ありの絵と決定的に同じ値になる。構図を1画素も動かさないことで、円盤の判定を画面全体の
/// 高輝度画素数でなく画素位置ごとの差分で行える(カメラを反対へ振って構図ごと変える旧設計は、地形・空・霞を
/// 含む全画素の視線が変わるため、円盤の位置を見ない差分しか取れなかった)。
pub(super) const 太陽円盤対照のファイル名: &str = "sun_disk_control";
