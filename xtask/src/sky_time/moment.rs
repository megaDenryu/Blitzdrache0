//! 検収が描く代表時刻の表。`--report-sky-state`の代表位相と同じ4つを選び、同じ場面を絵でも数でも語れるようにする。
//!
//! 一日内の秒は既定の一日の長さ(86400秒)での値である。夜明けと夕方はどちらも太陽高度がちょうど0であり、
//! 方位だけが東と西で反対になる。この2つは互いの鏡像に近いため、判定は隣り合う時刻の間だけで行う。

pub(super) struct 代表時刻 {
    /// 報告に出す名前。
    pub(super) 名前: &'static str,
    /// ダンプのファイル名に使う名前。パスはASCIIで保つ。
    pub(super) ファイル名: &'static str,
    pub(super) 一日内秒: &'static str,
}

pub(super) const 代表時刻一覧: [代表時刻; 4] = [
    代表時刻 {
        名前: "夜明け",
        ファイル名: "dawn",
        一日内秒: "21600",
    },
    代表時刻 {
        名前: "正午",
        ファイル名: "noon",
        一日内秒: "43200",
    },
    代表時刻 {
        名前: "夕方",
        ファイル名: "evening",
        一日内秒: "64800",
    },
    代表時刻 {
        名前: "夜",
        ファイル名: "night",
        一日内秒: "75600",
    },
];

/// 決定性を確かめるために2度描く時刻の添字。正午は空も地表も明るく、値の違いが最も出やすい。
pub(super) const 再描画する添字: usize = 1;

/// 夜明けの添字。夕方との対称性判定で使う。
pub(super) const 夜明けの添字: usize = 0;

/// 夕方の添字。夜明けとの対称性判定で使う。
pub(super) const 夕方の添字: usize = 2;

/// 夜の添字。夜だけに課す判定(方向光の寄与が0近傍であること)で使う。
pub(super) const 夜の添字: usize = 3;

/// 太陽円盤を画面へ入れる条件。17時(太陽高度約12度)を選ぶのは、大気LUT腕が円盤の透過率を視線ごとに
/// 大気で減衰させるためである。太陽高度ちょうど0(夕方64800秒)では経路長が最大になり、代表テクセルの実測
/// (地表に近い視線で緑1パーセント台まで減光)と同じ桁まで円盤が暗んで飽和しない。方位度は緯度35度・太陽赤緯0度の
/// 球面天文学(`sun_position.rs`)から18時とは別に求め直した値である。
pub(super) const 太陽円盤のファイル名: &str = "sun_disk";
pub(super) const 太陽円盤の一日内秒: &str = "61200";
pub(super) const 太陽円盤のカメラ方位度: &str = "99";

/// 太陽円盤の対照(負の対照)を撮るファイル名とカメラ方位。太陽円盤の判定は画面全体の高輝度画素数を
/// 数えるだけでは円盤の位置を見ないため、同じ時刻・同じ構図で太陽だけを画面の外へ出した対照との差分を取る。
/// 方位を180度反対(99+180=279)にするのは、水平視野角(縦視野60度・1280x720のアスペクト比から約91.5度)の
/// 半分46度弱に対して太陽が正反対の180度離れるため、対照側の画面には円盤が絶対に入らないことを角度だけで
/// 保証できるからである。
pub(super) const 太陽円盤対照のファイル名: &str = "sun_disk_control";
pub(super) const 太陽円盤対照のカメラ方位度: &str = "279";
