//! 1枚の絵から領域別の実測値を採る工程。受け取るのは絵と領域区分、返すのは判定が読む数値一式である。
//!
//! 明部は最大値でなくp95で測る。世界の点光源は時刻から導かないため夜でも小さな明部が残り、最大値だと
//! その数画素が時刻ごとの明るさを代表してしまう。暗部は「直接光が届いていない画素」の数であり、
//! 太陽の向きが動けば地形と植生のどの面が暗いかが変わるため、この数の変化が影と陰の動きを表す。

use super::region::{区分, 領域区分};
use crate::acceptance::{判定の破れ, 画素の番号, 読み戻し画像};
use crate::damage_band::{飽和の下限, 黒潰れの上限};

/// 暗部と認める明るさの上限。夜の地表(環境光のみ)がこの帯に収まり、正午の地表は大きく上回る。
const 暗部の明るさ上限: u16 = 64;
/// 太陽円盤と認める明るさの下限。3成分すべてがこの値以上の画素だけを数える。
pub(super) const 円盤の明るさ下限: u8 = 250;

pub(super) struct 領域別実測 {
    pub(super) 空平均色: [u16; 3],
    pub(super) 空の飽和画素数: u64,
    pub(super) 明部の第95百分位: u16, // ジオメトリ領域の明るさの95パーセンタイル。照明を受ける面の明るさを代表する
    pub(super) 明部の第99百分位: u16, // ジオメトリ領域の明るさの99パーセンタイル。夜に方向光の寄与が残っていないことを確かめる
    pub(super) 暗部画素数: u64,
    pub(super) 黒つぶれ画素数: u64,     // 3成分すべてが0の画素数。空も地表も下限を持つため常に0でなければならない
    pub(super) 地形の黒潰れ画素数: u64, // ジオメトリ領域のうち3成分すべてが黒潰れの上限以下の画素数。破綻防止帯が割合にして判定する
    pub(super) 地形の飽和画素数: u64,   // ジオメトリ領域のうち3成分すべてが飽和の下限以上の画素数。破綻防止帯が割合にして判定する
}

pub(super) fn 採る(絵: &読み戻し画像, 区分一覧: &領域区分) -> Result<領域別実測, 判定の破れ> {
    区分一覧.寸法が合うか(絵)?;
    let mut 空合計 = [0_u64; 3];
    let (mut 空飽和, mut 暗部, mut 黒つぶれ) = (0_u64, 0_u64, 0_u64);
    let (mut 地形の黒潰れ, mut 地形の飽和) = (0_u64, 0_u64);
    let mut 明るさ度数 = [0_u64; 256];
    for 添字 in 0..絵.画素数() {
        let 色 = 絵.番号の画素(画素の番号::生成する(添字));
        if 色.iter().all(|成分| *成分 == 0) {
            黒つぶれ += 1;
        }
        match 区分一覧.区分(添字) {
            区分::空 => {
                for (合計, 成分) in 空合計.iter_mut().zip(色) {
                    *合計 += u64::from(成分);
                }
                空飽和 += u64::from(色.iter().all(|成分| *成分 >= 円盤の明るさ下限));
            }
            区分::ジオメトリ => {
                let 明るさ = 明るさを求める(色);
                明るさ度数[usize::from(明るさ)] += 1;
                暗部 += u64::from(u16::from(明るさ) < 暗部の明るさ上限);
                地形の黒潰れ += u64::from(色.iter().all(|成分| *成分 <= 黒潰れの上限));
                地形の飽和 += u64::from(色.iter().all(|成分| *成分 >= 飽和の下限));
            }
        }
    }
    Ok(領域別実測 {
        空平均色: 平均を求める(空合計, 区分一覧.空画素数),
        空の飽和画素数: 空飽和,
        明部の第95百分位: 分位を求める(&明るさ度数, 区分一覧.幾何画素数, 95),
        明部の第99百分位: 分位を求める(&明るさ度数, 区分一覧.幾何画素数, 99),
        暗部画素数: 暗部,
        黒つぶれ画素数: 黒つぶれ,
        地形の黒潰れ画素数: 地形の黒潰れ,
        地形の飽和画素数: 地形の飽和,
    })
}

fn 明るさを求める(色: [u8; 3]) -> u8 {
    let 合計 = u16::from(色[0]) + u16::from(色[1]) + u16::from(色[2]);
    u8::try_from(合計 / 3).unwrap_or(u8::MAX)
}

/// 空の領域の成分ごとの平均色。
///
/// 注意: 1画素の成分は255以下であり、その平均もu16へ必ず収まる。収まらない値で止めるのは、
/// 起こりえない変換の失敗を判定の失敗として運ばないためである。
/// 件数が0でないことは`領域区分`の構築が課しており、この工程はそれを前提に割る。
fn 平均を求める(合計: [u64; 3], 件数: u64) -> [u16; 3] {
    let mut 平均 = [0_u16; 3];
    for (保存先, 値) in 平均.iter_mut().zip(合計) {
        *保存先 = u16::try_from(値 / 件数).unwrap_or(u16::MAX);
    }
    平均
}

fn 分位を求める(度数: &[u64; 256], 件数: u64, 百分率: u64) -> u16 {
    let 目標 = 件数 * 百分率 / 100;
    let mut 累計 = 0_u64;
    for (明るさ, 数) in 度数.iter().enumerate() {
        累計 += *数;
        if 累計 >= 目標 {
            return u16::try_from(明るさ).unwrap_or(u16::MAX);
        }
    }
    u16::MAX
}
