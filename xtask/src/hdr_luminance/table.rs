//! 人が読む形の出力。担当するのは時刻別の表と、入口の1行の要約である。
//!
//! 表と要約を1箇所に置くのは、どちらも同じ統計を人向けの文字列へ写すだけであり、桁数の決め方が離れると同じ値が2通りの精度で並ぶためである。

use super::statistics::輝度統計;
use crate::damage_band::割合にする;

pub(super) fn 表示する(標本一覧: &[(&'static str, 輝度統計)]) {
    println!("時刻\t最小EV\tp1EV\tp50EV\tp99EV\t最大EV\t0以下画素\t0以下割合\t非有限画素\t線形最小\t線形最大");
    for (名前, 統計) in 標本一覧 {
        println!(
            "{名前}\t{:.4}\t{:.4}\t{:.4}\t{:.4}\t{:.4}\t{}\t{:.6}\t{}\t{:.6}\t{:.6}",
            統計.最小のev,
            統計.p1のev,
            統計.p50のev,
            統計.p99のev,
            統計.最大のev,
            統計.非正の輝度の画素数,
            割合にする(統計.非正の輝度の画素数, 統計.全画素数),
            統計.非有限の輝度の画素数,
            統計.線形の最小,
            統計.線形の最大
        );
    }
}

pub(super) fn 要約の行(名前: &str, 統計: &輝度統計) -> String {
    format!(
        "{名前}は最小{:.2}EV・p1 {:.2}EV・p50 {:.2}EV・p99 {:.2}EV・最大{:.2}EV、0以下の輝度が{}画素({:.6})",
        統計.最小のev,
        統計.p1のev,
        統計.p50のev,
        統計.p99のev,
        統計.最大のev,
        統計.非正の輝度の画素数,
        割合にする(統計.非正の輝度の画素数, 統計.全画素数)
    )
}
