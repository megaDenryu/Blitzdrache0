//! この入口が持つ機械判定。受け取るのは1時刻ぶんの統計と時刻の名前、返すのは合否である。
//!
//! 判定を集計から分けるのは、「この入口が何を落とすか」を1箇所で読めるようにするためである。
//! 上限も下限も1つも持たない。範囲の制定はここで採った値を人が読んで決めることであり、期待値をこの入口に
//! 置くと、まだ決めていない範囲を検収側が先に決めたことになる。
//!
//! 件数を対象外にするのは、0以下の輝度の画素の計数が0でも意味を持つためである。

use super::statistics::輝度統計;
use crate::acceptance::{判定の名前, 判定の破れ};

/// 報告する値がすべて有限であることを確かめる。
pub(super) fn 値が有限であることを確かめる(統計: &輝度統計, 時刻名: &str) -> Result<(), 判定の破れ> {
    for (呼び名, 値) in [
        ("最小のEV", 統計.最小のev),
        ("p1のEV", 統計.p1のev),
        ("p50のEV", 統計.p50のev),
        ("p99のEV", 統計.p99のev),
        ("最大のEV", 統計.最大のev),
        ("線形の最小", 統計.線形の最小),
        ("線形の最大", 統計.線形の最大),
    ] {
        判定名を組む(時刻名, 呼び名).有限であることを課す(値)?;
    }
    Ok(())
}

fn 判定名を組む(時刻名: &str, 呼び名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{時刻名}の輝度統計の{呼び名}"))
}
