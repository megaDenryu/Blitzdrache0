//! 全時刻の統計を生値ファイルへ書き出す工程。受け取るのは書き先と時刻別の統計、返すものは無い。
//!
//! 生値を残すのは、範囲の制定を後から別の切り口で読み直すためである。標準出力の表は桁を丸めて並べるが、
//! 範囲の端を決めるには丸める前の値が要る。
//!
//! 注意: 1行が持つのは1時刻ぶんの画面全体の集約であり、画素ごとの値ではない。画素ごとの証拠が要るときは、
//! 同じディレクトリに残る`<時刻>.hdr32`が唯一の記録になる。

use std::path::Path;

use super::statistics::輝度統計;

pub(super) fn 生値を書く(書き先: &Path, 標本一覧: &[(&'static str, 輝度統計)]) -> Result<(), String> {
    let mut 本文 =
        String::from("時刻\t全画素数\t正の輝度の画素数\t0以下の画素数\t非有限の画素数\t最小EV\tp1EV\tp50EV\tp99EV\t最大EV\t線形最小\t線形最大\n");
    for (名前, 統計) in 標本一覧 {
        本文.push_str(&行にする(名前, 統計));
    }
    std::fs::write(書き先, 本文).map_err(|誤り| format!("{}を書けなかった: {誤り}", 書き先.display()))
}

fn 行にする(名前: &str, 統計: &輝度統計) -> String {
    format!(
        "{名前}\t{}\t{}\t{}\t{}\t{:.6}\t{:.6}\t{:.6}\t{:.6}\t{:.6}\t{:.9}\t{:.9}\n",
        統計.全画素数,
        統計.正の輝度の画素数,
        統計.非正の輝度の画素数,
        統計.非有限の輝度の画素数,
        統計.最小のev,
        統計.p1のev,
        統計.p50のev,
        統計.p99のev,
        統計.最大のev,
        統計.線形の最小,
        統計.線形の最大
    )
}
