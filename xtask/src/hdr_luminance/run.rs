//! 1時刻ぶんの起動の指定。受け取るのは代表時刻、返すのは実行環境へ渡す起動指定である。
//! 起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! シーン名を`terrain_visual`にすることが、庭を正面から見る初期カメラと、書き換えもピクセル判定も持たない検収計画と、天空の遠方環境の間接照明方針を同時に選ばせる。空もポスト処理も本番の経路のままにするのは、自動露出が見るのが本番の絵と同じHDRカラーだからである。監視対象シェーダーは`terrain-visual`と同じく指定しない。
//!
//! リリースで走らせるのは、この入口が1時刻ごとに1280x720の画素を全部CPUへ運んで並べ替えるためである。
//! デバッグで4回走らせると、絵を撮るだけの`terrain-visual`より更に長い実行時間になる。
//! 画素の値は最適化水準で変わらない(絵はGPUが作り、CPU側の浮動小数の意味づけも最適化で変わらない)。
//! 時間再構成は`--no-taa`で外す。この入口の判定がバイト一致に依るため、フレームをまたぐ混合が入ると前のフレームの残りが絵に混ざる。

use std::path::PathBuf;

use crate::acceptance::{アプリの起こし方, アプリの起動指定, 描画フレーム数, 描画検収の実行環境, 検収エラー};
use crate::visual_sample_world::{目視見本世界のアセットルートを作る, 目視見本世界のシーン名};

/// 描くフレーム数。`terrain-visual`と同じ本数であり、空と間接照明の焼き上げが定常へ入る状態まで進める。
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(120);

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoにリリース版を構築させて起動する,
        目視見本世界のアセットルートを作る(),
        出力ディレクトリ,
    )
}

pub(super) fn 時刻の起動指定を組み立てる(一日内秒: &str) -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(目視見本世界のシーン名, フレーム数)
        .値を持つ選択肢を足す("--time-of-day", 一日内秒)
        .選択肢を足す("--no-taa")
}
