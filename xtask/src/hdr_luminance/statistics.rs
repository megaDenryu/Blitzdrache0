//! 圧縮前のHDRカラーからlog2輝度の分布を作る工程。受け取るのは1時刻ぶんの画像、返すのはその画面全体の統計である。
//!
//! 輝度は`crate::relative_luminance`の相対輝度で定める。単位はEVであり、輝度1.0が0EVになる。
//! 画素を選り分けずに画面全体で採るのは、自動露出が画面全体のヒストグラムを見るためである。空も太陽円盤も含める。
//!
//! 画素は「正の輝度」「0以下の輝度」「非有限」の3つのどれか1つに必ず入る。
//! log2は正の値にしか定まらないため、百分位は正の輝度の画素だけを並べて採り、残る2つは件数として報告する。
//! 黙って捨てると、下限ビンの設計に要る「log2が定まらない画素がどれだけあるか」が報告から消える。

use blitz_math::{パーセンタイル順位, 昇順に並べた標本列, 順位から添字を選ぶ規則};

use super::error::圧縮前の輝度分布の計測エラー;
use crate::acceptance::{判定の名前, 圧縮前のHDR画像};
use crate::relative_luminance::相対輝度;

/// この統計が添字を選ぶ規則。寄せる前からこの規則であり、報告の値を動かさないために変えない。
const 添字を選ぶ規則: 順位から添字を選ぶ規則 = 順位から添字を選ぶ規則::最後の添字を基準にした四捨五入;

/// log2輝度の分布を作れる実行の条件。1件も無ければ、続く百分位が意味を持たないまま消費側へ渡る。
const 正の輝度を持つ画素: 判定の名前 = 判定の名前::定数から生成する("正の輝度を持つ画素(1つも無いとlog2輝度の分布を作れない)");

pub(super) struct 輝度統計 {
    pub(super) 全画素数: u64,
    pub(super) 正の輝度の画素数: u64,
    pub(super) 非正の輝度の画素数: u64,
    pub(super) 非有限の輝度の画素数: u64,
    pub(super) 最小の露出段: f64,
    pub(super) 下側一パーセンタイルの露出段: f64,
    pub(super) 五十パーセンタイルの露出段: f64,
    pub(super) 上側一パーセンタイルの露出段: f64,
    pub(super) 最大の露出段: f64,
    pub(super) 線形の最小: f64, // 線形の最小/最大は有限の輝度を持つ画素の線形値。0以下の画素も含むためEVの最小と対応するとは限らない
    pub(super) 線形の最大: f64,
}

pub(super) fn 集計する(画像: &圧縮前のHDR画像) -> Result<輝度統計, 圧縮前の輝度分布の計測エラー> {
    let mut log2輝度 = Vec::with_capacity(画像.画素数());
    let (mut 非正, mut 非有限) = (0_u64, 0_u64);
    let (mut 線形の最小, mut 線形の最大) = (f64::INFINITY, f64::NEG_INFINITY);
    for 画素 in 画像.画素列() {
        let 輝度 = 相対輝度(画素);
        if !輝度.is_finite() {
            非有限 += 1;
            continue;
        }
        線形の最小 = 線形の最小.min(輝度);
        線形の最大 = 線形の最大.max(輝度);
        if 輝度 <= 0.0 {
            非正 += 1;
            continue;
        }
        log2輝度.push(輝度.log2());
    }
    let 標本列 = 昇順に並べた標本列::並べ替えて生成する(&mut log2輝度);
    組み立てる(画像, &標本列, (非正, 非有限), (線形の最小, 線形の最大))
}

fn 組み立てる(画像: &圧縮前のHDR画像, 標本列: &昇順に並べた標本列<'_, f64>, 除外件数: (u64, u64), 線形: (f64, f64)) -> Result<輝度統計, 圧縮前の輝度分布の計測エラー> {
    let 件数 = 数へ写す("正の輝度の画素数", 標本列.件数())?;
    if 件数 == 0 {
        return Err(正の輝度を持つ画素.あるはずのものが無い破れ().into());
    }
    Ok(輝度統計 {
        全画素数: 数へ写す("画素数", 画像.画素数())?,
        正の輝度の画素数: 件数,
        非正の輝度の画素数: 除外件数.0,
        非有限の輝度の画素数: 除外件数.1,
        最小の露出段: 百分位(標本列, 0.0)?,
        下側一パーセンタイルの露出段: 百分位(標本列, 1.0)?,
        五十パーセンタイルの露出段: 百分位(標本列, 50.0)?,
        上側一パーセンタイルの露出段: 百分位(標本列, 99.0)?,
        最大の露出段: 百分位(標本列, 100.0)?,
        線形の最小: 線形.0,
        線形の最大: 線形.1,
    })
}

fn 数へ写す(呼び名: &'static str, 画素数: usize) -> Result<u64, 圧縮前の輝度分布の計測エラー> {
    u64::try_from(画素数).map_err(|_| 圧縮前の輝度分布の計測エラー::画素数が数へ収まらない { 呼び名, 画素数 })
}

fn 百分位(標本列: &昇順に並べた標本列<'_, f64>, 順位: f32) -> Result<f64, 圧縮前の輝度分布の計測エラー> {
    標本列
        .パーセンタイル値を求める(パーセンタイル順位::百分率から生成する(順位), 添字を選ぶ規則)
        .ok_or(圧縮前の輝度分布の計測エラー::パーセンタイル値を採れなかった { 順位, 件数: 標本列.件数() })
}
