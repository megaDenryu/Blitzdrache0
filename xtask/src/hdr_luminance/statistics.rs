//! 圧縮前のHDRカラーからlog2輝度の分布を作る工程。受け取るのは1時刻ぶんの画像、返すのはその画面全体の統計である。
//!
//! 輝度は相対輝度Y = 0.2126R + 0.7152G + 0.0722B(BT.709の係数)で定める。単位はEVであり、輝度1.0が0EVになる。
//! 画素を選り分けずに画面全体で採るのは、自動露出が画面全体のヒストグラムを見るためである。空も太陽円盤も含める。
//!
//! 画素は「正の輝度」「0以下の輝度」「非有限」の3つのどれか1つに必ず入る。
//! log2は正の値にしか定まらないため、百分位は正の輝度の画素だけを並べて採り、残る2つは件数として報告する。
//! 黙って捨てると、下限ビンの設計に要る「log2が定まらない画素がどれだけあるか」が報告から消える。

use super::image::{HDR画像, 画素あたり成分数};

const 赤の重み: f64 = 0.2126;
const 緑の重み: f64 = 0.7152;
const 青の重み: f64 = 0.0722;

pub(super) struct 輝度統計 {
    pub(super) 全画素数: u64,
    pub(super) 正の輝度の画素数: u64,
    pub(super) 非正の輝度の画素数: u64,
    pub(super) 非有限の輝度の画素数: u64,
    pub(super) 最小のev: f64,
    pub(super) p1のev: f64,
    pub(super) p50のev: f64,
    pub(super) p99のev: f64,
    pub(super) 最大のev: f64,
    /// 有限の輝度を持つ画素の線形値の最小と最大。0以下の画素も含めるため、EVの最小と対応するとは限らない。
    pub(super) 線形の最小: f64,
    pub(super) 線形の最大: f64,
}

impl 輝度統計 {
    /// 報告する値がすべて有限であることを確かめる。件数は対象外である(0以下の画素の計数は0でも意味を持つ)。
    pub(super) fn 値が有限であることを確かめる(&self, 時刻名: &str) -> Result<(), String> {
        let 値一覧 = [
            self.最小のev,
            self.p1のev,
            self.p50のev,
            self.p99のev,
            self.最大のev,
            self.線形の最小,
            self.線形の最大,
        ];
        if 値一覧.iter().all(|値| 値.is_finite()) {
            return Ok(());
        }
        Err(format!("{時刻名}の輝度統計に有限でない値がある: {値一覧:?}"))
    }
}

pub(super) fn 集計する(画像: &HDR画像) -> Result<輝度統計, String> {
    let mut log2輝度 = Vec::with_capacity(画像.画素数);
    let (mut 非正, mut 非有限) = (0_u64, 0_u64);
    let (mut 線形の最小, mut 線形の最大) = (f64::INFINITY, f64::NEG_INFINITY);
    for 画素 in 画像.成分列.chunks_exact(画素あたり成分数) {
        let 輝度 = 相対輝度(画素);
        if !輝度.is_finite() {
            非有限 += 1;
            continue;
        }
        線形の最小 = 線形の最小.min(輝度);
        線形の最大 = 線形の最大.max(輝度);
        if 輝度 <= 0.0 {
            非正 += 1;
            continue;
        }
        log2輝度.push(輝度.log2());
    }
    log2輝度.sort_by(f64::total_cmp);
    組み立てる(画像, &log2輝度, (非正, 非有限), (線形の最小, 線形の最大))
}

fn 組み立てる(画像: &HDR画像, 昇順: &[f64], 除外件数: (u64, u64), 線形: (f64, f64)) -> Result<輝度統計, String> {
    let 件数 = u64::try_from(昇順.len()).map_err(|誤り| format!("正の輝度の画素数がu64に収まらない: {誤り}"))?;
    if 件数 == 0 {
        return Err("正の輝度を持つ画素が1つも無く、log2輝度の分布を作れない".to_string());
    }
    Ok(輝度統計 {
        全画素数: u64::try_from(画像.画素数).map_err(|誤り| format!("画素数がu64に収まらない: {誤り}"))?,
        正の輝度の画素数: 件数,
        非正の輝度の画素数: 除外件数.0,
        非有限の輝度の画素数: 除外件数.1,
        最小のev: 百分位(昇順, 件数, 0)?,
        p1のev: 百分位(昇順, 件数, 1)?,
        p50のev: 百分位(昇順, 件数, 50)?,
        p99のev: 百分位(昇順, 件数, 99)?,
        最大のev: 百分位(昇順, 件数, 100)?,
        線形の最小: 線形.0,
        線形の最大: 線形.1,
    })
}

/// 昇順に並んだ列から百分位を最近接順位で採る。添字は`四捨五入(百分率 × (件数 - 1) ÷ 100)`であり、整数の演算だけで求めるのは実数の添字を整数へ落とす丸めを2通り持たないためである。
fn 百分位(昇順: &[f64], 件数: u64, 百分率: u64) -> Result<f64, String> {
    let 添字 = usize::try_from((百分率 * (件数 - 1) + 50) / 100).map_err(|誤り| format!("百分位の添字がusizeに収まらない: {誤り}"))?;
    昇順.get(添字).copied().ok_or_else(|| format!("百分位{百分率}の添字{添字}が列の外にある"))
}

fn 相対輝度(画素: &[f32]) -> f64 {
    f64::from(画素[0]) * 赤の重み + f64::from(画素[1]) * 緑の重み + f64::from(画素[2]) * 青の重み
}
