//! 圧縮前のHDRカラーからlog2輝度の分布を作る工程。受け取るのは1時刻ぶんの画像、返すのはその画面全体の統計である。
//!
//! 輝度は`crate::relative_luminance`の相対輝度で定める。単位はEVであり、輝度1.0が0EVになる。
//! 画素を選り分けずに画面全体で採るのは、自動露出が画面全体のヒストグラムを見るためである。空も太陽円盤も含める。
//!
//! 画素は「正の輝度」「0以下の輝度」「非有限」の3つのどれか1つに必ず入る。
//! log2は正の値にしか定まらないため、百分位は正の輝度の画素だけを並べて採り、残る2つは件数として報告する。
//! 黙って捨てると、下限ビンの設計に要る「log2が定まらない画素がどれだけあるか」が報告から消える。

use super::error::圧縮前の輝度分布の計測エラー;
use crate::acceptance::{判定の名前, 圧縮前のHDR画像};
use crate::relative_luminance::相対輝度;

/// log2輝度の分布を作れる実行の条件。1件も無ければ、続く百分位が意味を持たないまま消費側へ渡る。
const 正の輝度を持つ画素: 判定の名前 = 判定の名前::定数から生成する("正の輝度を持つ画素(1つも無いとlog2輝度の分布を作れない)");

pub(super) struct 輝度統計 {
    pub(super) 全画素数: u64,
    pub(super) 正の輝度の画素数: u64,
    pub(super) 非正の輝度の画素数: u64,
    pub(super) 非有限の輝度の画素数: u64,
    pub(super) 最小のev: f64,
    pub(super) p1のev: f64,
    pub(super) p50のev: f64,
    pub(super) p99のev: f64,
    pub(super) 最大のev: f64,
    /// 有限の輝度を持つ画素の線形値の最小と最大。0以下の画素も含めるため、EVの最小と対応するとは限らない。
    pub(super) 線形の最小: f64,
    pub(super) 線形の最大: f64,
}

pub(super) fn 集計する(画像: &圧縮前のHDR画像) -> Result<輝度統計, 圧縮前の輝度分布の計測エラー> {
    let mut log2輝度 = Vec::with_capacity(画像.画素数());
    let (mut 非正, mut 非有限) = (0_u64, 0_u64);
    let (mut 線形の最小, mut 線形の最大) = (f64::INFINITY, f64::NEG_INFINITY);
    for 画素 in 画像.画素列() {
        let 輝度 = 相対輝度(画素);
        if !輝度.is_finite() {
            非有限 += 1;
            continue;
        }
        線形の最小 = 線形の最小.min(輝度);
        線形の最大 = 線形の最大.max(輝度);
        if 輝度 <= 0.0 {
            非正 += 1;
            continue;
        }
        log2輝度.push(輝度.log2());
    }
    log2輝度.sort_by(f64::total_cmp);
    組み立てる(画像, &log2輝度, (非正, 非有限), (線形の最小, 線形の最大))
}

fn 組み立てる(
    画像: &圧縮前のHDR画像,
    昇順: &[f64],
    除外件数: (u64, u64),
    線形: (f64, f64),
) -> Result<輝度統計, 圧縮前の輝度分布の計測エラー> {
    let 件数 = 数へ写す("正の輝度の画素数", 昇順.len())?;
    if 件数 == 0 {
        return Err(正の輝度を持つ画素.あるはずのものが無い破れ().into());
    }
    Ok(輝度統計 {
        全画素数: 数へ写す("画素数", 画像.画素数())?,
        正の輝度の画素数: 件数,
        非正の輝度の画素数: 除外件数.0,
        非有限の輝度の画素数: 除外件数.1,
        最小のev: 百分位(昇順, 件数, 0)?,
        p1のev: 百分位(昇順, 件数, 1)?,
        p50のev: 百分位(昇順, 件数, 50)?,
        p99のev: 百分位(昇順, 件数, 99)?,
        最大のev: 百分位(昇順, 件数, 100)?,
        線形の最小: 線形.0,
        線形の最大: 線形.1,
    })
}

fn 数へ写す(呼び名: &'static str, 画素数: usize) -> Result<u64, 圧縮前の輝度分布の計測エラー> {
    u64::try_from(画素数).map_err(|_| 圧縮前の輝度分布の計測エラー::画素数が数へ収まらない { 呼び名, 画素数 })
}

/// 昇順に並んだ列から、`四捨五入(百分率 × (件数 - 1) ÷ 100)`で求めた添字の値を百分位として採る。統計の「最近接順位法」(`ceil(百分率 × 件数 ÷ 100) - 1`)とは端の扱いが違う別の式であるため、その名では呼ばない。
fn 百分位(昇順: &[f64], 件数: u64, 百分率: u64) -> Result<f64, 圧縮前の輝度分布の計測エラー> {
    let 求めた添字 = (百分率 * (件数 - 1) + 50) / 100;
    let 添字 = usize::try_from(求めた添字)
        .map_err(|_| 圧縮前の輝度分布の計測エラー::百分位の添字が数へ収まらない {
            百分率, 添字: 求めた添字
        })?;
    昇順
        .get(添字)
        .copied()
        .ok_or(圧縮前の輝度分布の計測エラー::百分位の添字が列の外にある { 百分率, 添字 })
}
