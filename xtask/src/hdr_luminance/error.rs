//! 圧縮前の輝度分布の計測が返す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。
//! 様式は`acceptance/error.rs`と`depth_prepass_cost/error.rs`に倣う。
//!
//! 検収の器の破れと判定の破れを枝で内包するのは、この入口が起動と読み戻しと判定と生値の書き出しを
//! 一続きに通すためである。4つを別の型で返すと、通す側が段ごとに変換を書くことになる。
//!
//! 判定でも報告の読み取りでもない破れをここが持つのは、目視見本世界の用意と生値の書き出しと
//! 百分位の添字の組み立てが、どれも判定の外側の工程だからである。目視見本世界の用意だけ理由を文で持つのは、
//! その工程が別の入口の持ち物であり、失敗の種類をこちらで数え上げられないためである。
//! 人が読む1文へ写すのは`display`が持つ。

mod display;

use std::path::PathBuf;

use crate::acceptance::{判定の破れ, 検収エラー};

#[derive(Debug)]
pub(super) enum 圧縮前の輝度分布の計測エラー {
    検収の器が破れた(検収エラー),
    判定が破れた(判定の破れ),
    目視見本世界を用意できなかった(crate::world_setup::検収世界の用意の破れ),
    画素数が数へ収まらない { 呼び名: &'static str, 画素数: usize },
    百分位の添字が数へ収まらない { 百分率: u64, 添字: u64 },
    百分位の添字が列の外にある { 百分率: u64, 添字: usize }, // 昇順に並べた列の外を指す添字が出た。到達すれば百分位の添字の式が列の長さと食い違っている
    生値を書けなかった { パス: PathBuf, 誤り: std::io::Error },
}

impl std::error::Error for 圧縮前の輝度分布の計測エラー {}

impl From<検収エラー> for 圧縮前の輝度分布の計測エラー {
    fn from(破れ: 検収エラー) -> Self {
        Self::検収の器が破れた(破れ)
    }
}

impl From<判定の破れ> for 圧縮前の輝度分布の計測エラー {
    fn from(破れ: 判定の破れ) -> Self {
        Self::判定が破れた(破れ)
    }
}
