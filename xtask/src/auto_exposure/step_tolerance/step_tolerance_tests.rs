//! 目標補正段の近さの判定の検査。担当するのは「どの入力で合格し、どの入力で落ちるか」を固定することだけである。
//!
//! 非有限の場合を先に固定するのは、非数どうしの比較がどの向きでも偽になり、差だけを許容と比べる書き方では
//! GPUの目標が非数になった退行が合格へ落ちるためである。この判定は検収の新しい契約であり、発火経路を検査で埋める。

#![allow(clippy::unwrap_used)]

use super::{許容する段の差, 近さを判定する};

#[test]
fn 許容の内側は合格する() {
    assert!(近さを判定する("-0.8810451", "-0.8810451").is_ok());
    assert!(近さを判定する("0.0", "-0.0000005").is_ok());
}

#[test]
fn 許容ちょうどは合格する() {
    let 差ちょうど = format!("{}", -許容する段の差);
    assert!(近さを判定する("0.0", &差ちょうど).is_ok(), "差{差ちょうど}が落ちた");
}

#[test]
fn 許容を超えると落ちる() {
    let 誤り = 近さを判定する("0.0", "-0.000002").unwrap_err();
    assert!(誤り.contains("許容"), "許容超過の理由になっていない: {誤り}");
}

#[test]
fn 片方が非数なら落ちる() {
    for (正本, 写し) in [("NaN", "-0.88"), ("-0.88", "NaN")] {
        let 誤り = 近さを判定する(正本, 写し).unwrap_err();
        assert!(誤り.contains("有限でない"), "{正本}と{写し}が有限でないと言われていない: {誤り}");
    }
}

#[test]
fn 両方が非数でも落ちる() {
    let 誤り = 近さを判定する("NaN", "NaN").unwrap_err();
    assert!(誤り.contains("有限でない"), "非数どうしが合格した: {誤り}");
}

#[test]
fn 無限大は符号が同じでも違っても落ちる() {
    for (正本, 写し) in [("inf", "inf"), ("-inf", "-inf"), ("inf", "-inf"), ("-0.88", "inf")] {
        let 誤り = 近さを判定する(正本, 写し).unwrap_err();
        assert!(誤り.contains("有限でない"), "{正本}と{写し}が合格した: {誤り}");
    }
}

#[test]
fn 数として読めない語は落ちる() {
    let 誤り = 近さを判定する("導出不能", "-0.88").unwrap_err();
    assert!(誤り.contains("数として読めない"), "読めない語の理由になっていない: {誤り}");
}
