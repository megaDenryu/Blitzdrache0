//! 読み解いた報告に対する機械判定。受け取るのは報告、返すのは合否である。成功時の1行の組み立ては`summary`にある。
//!
//! 整数で作る値は厳密に見る。ヒストグラムの件数と、そこから作る添字の重み付き総和がそれであり、後者が導出の
//! 正しさを見る柱である。整数の加算は足す順にも結合の順にも依存しないため、この2つは必ずバイト一致する。
//! 目標補正段だけは許容を置く。その許容と根拠は`step_tolerance`が所有し、ここは呼ぶだけである。

use super::parse::自動露出の報告;
use super::step_tolerance::近さを判定する;
use crate::acceptance::{判定の名前, 判定の破れ};

const 枠の一致: 判定の名前 = 判定の名前::定数から生成する("CPU正本とGPUの0以下または非有限の件数の一致");
/// 整数であるため足す順にも結合の順にも依存せず、食い違いは写しの誤りを意味する。
const 導出の整数の中間値: 判定の名前 = 判定の名前::定数から生成する("CPU正本とGPUの導出の整数の中間値");
/// 未初期化のままなら、集計か導出がGPUで走っていない。
const 露出状態の初期化: 判定の名前 = 判定の名前::定数から生成する("120フレーム描いた後の露出状態の初期化");
/// 目視見本の庭では導出できないフレームは起こらない。
const 導出不能フレーム数: 判定の名前 = 判定の名前::定数から生成する("導出できなかったフレームの回数");
const 追従中の補正段: 判定の名前 = 判定の名前::定数から生成する("同じ条件の2実行で追従中の補正段");
const ビンへ入った総数: 判定の名前 = 判定の名前::定数から生成する("同じ条件の2実行でビンへ入った総数");
/// 融合しない計算が答える添字と違えば、積和融合が起きている疑いがある。
const 探り色が入ったビン: 判定の名前 = 判定の名前::定数から生成する("探り色が入ったビンの添字");
/// 1件も無ければ背景が探り色で埋まっていない。
const 探り色のビンへ入った画素: 判定の名前 = 判定の名前::定数から生成する("探り色のビンへ入った画素");
const 探り色のビンの件数: 判定の名前 = 判定の名前::定数から生成する("探り色のビンの件数のCPU正本とGPUの一致");

pub(super) fn 一致を判定する(報告: &自動露出の報告) -> Result<(), 判定の破れ> {
    ヒストグラムの一致の判定名(報告).真であることを課す(報告.ビン一致)?;
    枠の一致.真であることを課す(報告.枠一致)?;
    導出の整数の中間値.綴りの一致を課す(&報告.gpu添字の重み付き総和, &報告.cpu添字の重み付き総和)?;
    近さを判定する(&報告.cpu目標補正段, &報告.gpu目標補正段)?;
    露出状態の初期化.真であることを課す(報告.初期化済み)?;
    導出不能フレーム数.綴りの一致を課す(&報告.導出不能フレーム数, "0")
}

fn ヒストグラムの一致の判定名(報告: &自動露出の報告) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "CPU正本とGPUのヒストグラムの一致(最初の食い違いビン={})",
        報告.最初の食い違いビン
    ))
}

/// 同じ条件の2実行が同じ適応系列の終端へ着くことを見る。経過秒が固定の刻みであるため、
/// 同じ入力からは同じ補正段が出る。
pub(super) fn 二実行の一致を判定する(一回目: &自動露出の報告, 二回目: &自動露出の報告) -> Result<(), 判定の破れ> {
    追従中の補正段.綴りの一致を課す(&二回目.gpu補正段, &一回目.gpu補正段)?;
    ビンへ入った総数.綴りの一致を課す(&二回目.ビンへ入った総数, &一回目.ビンへ入った総数)
}

/// 探り色が期待どおりのビンへ入り、その位置にCPUとGPUが同じ件数を置いたことを見る。
/// 件数が0でないことを別に見るのは、探り色の画素が1つも描かれていない実行を「一致した」と読み替えないためである。
pub(super) fn 探り色を判定する(報告: &自動露出の報告) -> Result<(), 判定の破れ> {
    探り色が入ったビン.綴りの一致を課す(&報告.探り色のビン, super::run::探り色のビンの添字)?;
    if 報告.探り色のcpu件数 == "0" {
        return Err(探り色のビンへ入った画素.あるはずのものが無い破れ());
    }
    探り色のビンの件数.綴りの一致を課す(&報告.探り色のgpu件数, &報告.探り色のcpu件数)
}
