//! 読み解いた報告に対する機械判定と要約の組み立て。受け取るのは報告、返すのは合否である。
//!
//! 補正段の一致を文字列のまま比べるのは、報告に出た10進表記が同じであることを見るためである。
//! 数として読み直して許容差で比べると、許容差の大きさという新しい判断がこの入口に住むことになる。

use super::parse::自動露出の報告;

pub(super) fn 一致を判定する(報告: &自動露出の報告) -> Result<(), String> {
    if !報告.ビン一致 {
        return Err(format!(
            "CPU正本とGPUのヒストグラムが食い違う(最初の食い違いビン={})",
            報告.最初の食い違いビン
        ));
    }
    if !報告.枠一致 {
        return Err("CPU正本とGPUで0以下または非有限の件数が食い違う".to_string());
    }
    if 報告.cpu目標補正段 != 報告.gpu目標補正段 {
        return Err(format!(
            "CPU正本の目標補正段{}とGPUの目標補正段{}が一致しない",
            報告.cpu目標補正段, 報告.gpu目標補正段
        ));
    }
    if !報告.初期化済み {
        return Err("120フレーム描いても露出状態が未初期化のままである(集計か導出がGPUで走っていない)".to_string());
    }
    if 報告.導出不能フレーム数 != "0" {
        return Err(format!(
            "導出できなかったフレームが{}回ある(目視見本の庭では起こらないはずである)",
            報告.導出不能フレーム数
        ));
    }
    Ok(())
}

/// 同じ条件の2実行が同じ適応系列の終端へ着くことを見る。経過秒が固定の刻みであるため、
/// 同じ入力からは同じ補正段が出る。
pub(super) fn 二実行の一致を判定する(一回目: &自動露出の報告, 二回目: &自動露出の報告) -> Result<(), String> {
    if 一回目.gpu補正段 != 二回目.gpu補正段 {
        return Err(format!(
            "同じ条件の2実行で追従中の補正段が違う({}と{})",
            一回目.gpu補正段, 二回目.gpu補正段
        ));
    }
    if 一回目.ビンへ入った総数 != 二回目.ビンへ入った総数 {
        return Err(format!(
            "同じ条件の2実行でビンへ入った総数が違う({}と{})",
            一回目.ビンへ入った総数, 二回目.ビンへ入った総数
        ));
    }
    Ok(())
}

pub(super) fn 要約を組む(報告: &自動露出の報告, 出力先: &std::path::Path) -> String {
    format!(
        "validationの指摘0件、CPU正本とGPUの全128ビンと2つの枠が一致(ビンへ入った総数{})、目標補正段は双方{}、追従中の補正段{}で2実行が一致、導出不能フレーム0回、上端到達率{}・下端到達率{}。圧縮前のHDRは{}にある",
        報告.ビンへ入った総数,
        報告.cpu目標補正段,
        報告.gpu補正段,
        報告.上端到達率,
        報告.下端到達率,
        出力先.display()
    )
}
