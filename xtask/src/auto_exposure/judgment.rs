//! 読み解いた報告に対する機械判定。受け取るのは報告、返すのは合否である。成功時の1行の組み立ては`summary`にある。
//!
//! 整数で作る値は厳密に見る。ヒストグラムの件数と、そこから作る添字の重み付き総和がそれであり、後者が導出の
//! 正しさを見る柱である。整数の加算は足す順にも結合の順にも依存しないため、この2つは必ずバイト一致する。
//! 目標補正段だけは許容を置く。整数の総和から平均を作る最後の3演算(語から実数への変換・除算・1次式)に
//! CPUとGPUの差の余地があり、とりわけ単精度の除算はVulkanが厳密な丸めを要求しないためである。

use super::parse::自動露出の報告;

/// 目標補正段に許す食い違い(EV)。整数の中間値が一致した後の、最後の3演算ぶんだけの余地である。
/// 明るさの比で1.0000007倍であり、絵にも判定にも現れない。
const 許容する段の差: f32 = 1.0e-6;

pub(super) fn 一致を判定する(報告: &自動露出の報告) -> Result<(), String> {
    if !報告.ビン一致 {
        return Err(format!(
            "CPU正本とGPUのヒストグラムが食い違う(最初の食い違いビン={})",
            報告.最初の食い違いビン
        ));
    }
    if !報告.枠一致 {
        return Err("CPU正本とGPUで0以下または非有限の件数が食い違う".to_string());
    }
    if 報告.cpu添字の重み付き総和 != 報告.gpu添字の重み付き総和 {
        return Err(format!(
            "導出の整数の中間値が食い違う(CPU正本{}・GPU{})。整数であるため足す順にも結合の順にも依存せず、食い違いは写しの誤りを意味する",
            報告.cpu添字の重み付き総和, 報告.gpu添字の重み付き総和
        ));
    }
    目標補正段の近さを判定する(&報告.cpu目標補正段, &報告.gpu目標補正段)?;
    if !報告.初期化済み {
        return Err("120フレーム描いても露出状態が未初期化のままである(集計か導出がGPUで走っていない)".to_string());
    }
    if 報告.導出不能フレーム数 != "0" {
        return Err(format!(
            "導出できなかったフレームが{}回ある(目視見本の庭では起こらないはずである)",
            報告.導出不能フレーム数
        ));
    }
    Ok(())
}

/// 同じ条件の2実行が同じ適応系列の終端へ着くことを見る。経過秒が固定の刻みであるため、
/// 同じ入力からは同じ補正段が出る。
pub(super) fn 二実行の一致を判定する(一回目: &自動露出の報告, 二回目: &自動露出の報告) -> Result<(), String> {
    if 一回目.gpu補正段 != 二回目.gpu補正段 {
        return Err(format!(
            "同じ条件の2実行で追従中の補正段が違う({}と{})",
            一回目.gpu補正段, 二回目.gpu補正段
        ));
    }
    if 一回目.ビンへ入った総数 != 二回目.ビンへ入った総数 {
        return Err(format!(
            "同じ条件の2実行でビンへ入った総数が違う({}と{})",
            一回目.ビンへ入った総数, 二回目.ビンへ入った総数
        ));
    }
    Ok(())
}

/// 段の差をEVの絶対値で見る。相対で見ないのは、目標が「目標中間灰の対数輝度 - 平均」の引き算であり、平均の最後の数ビットの食い違いが桁落ちで相対値としては大きく見えるためである。絵に効くのは段の差そのものである。
fn 目標補正段の近さを判定する(正本: &str, 写し: &str) -> Result<(), String> {
    let 読む = |語: &str| 語.parse::<f32>().map_err(|誤り| format!("目標補正段を数として読めない: {語}({誤り})"));
    let 差 = (読む(正本)? - 読む(写し)?).abs();
    if 差 > 許容する段の差 {
        return Err(format!(
            "CPU正本の目標補正段{正本}とGPUの目標補正段{写し}の差が{差}EVで、許容{許容する段の差}EVを超える"
        ));
    }
    Ok(())
}

/// 探り色が期待どおりのビンへ入り、その位置にCPUとGPUが同じ件数を置いたことを見る。
/// 件数が0でないことを別に見るのは、探り色の画素が1つも描かれていない実行を「一致した」と読み替えないためである。
pub(super) fn 探り色を判定する(報告: &自動露出の報告) -> Result<(), String> {
    if 報告.探り色のビン != super::run::探り色のビンの添字 {
        return Err(format!(
            "探り色が入ったビンが{}で、融合しない計算が答える{}と違う(積和融合が起きている疑いがある)",
            報告.探り色のビン,
            super::run::探り色のビンの添字
        ));
    }
    if 報告.探り色のcpu件数 == "0" {
        return Err("探り色のビンへ入った画素が1件も無い(背景が探り色で埋まっていない)".to_string());
    }
    if 報告.探り色のcpu件数 != 報告.探り色のgpu件数 {
        return Err(format!(
            "探り色のビンの件数がCPU正本{}とGPU{}で違う",
            報告.探り色のcpu件数, 報告.探り色のgpu件数
        ));
    }
    Ok(())
}
