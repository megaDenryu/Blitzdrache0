//! 1条件ぶんの起動の指定と、その実行の報告の読み解き。受け取るのは実行環境と実行名と時刻と探り色の扱い、
//! 返すのはその実行が出した自動露出の報告である。起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! 目視見本の庭(`terrain_visual`)を本番の描画経路で描くのは、判定の対象がその世界の本番の絵だからである。
//! 圧縮前の画素を書き出させるのは、CPU正本の集計が読むのが集計と同じHDR中間画像でなければならないためである
//! (書き出したファイル自体は証拠として残すが、この入口は読み戻さない)。
//!
//! リリースで走らせるのは、1実行ごとに1280x720の画素をCPUで数え直すためである。画素の値は最適化水準で変わらない。
//! 時間再構成は`--no-taa`で外す。この入口の判定がバイト一致に依るため、フレームをまたぐ混合が入ると前のフレームの残りが絵に混ざる。

use std::path::PathBuf;

use super::parse::{自動露出の報告, 読み解く};
use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 描画フレーム数, 描画検収の実行環境, 書き出しの形式, 検収の実行名, 検収エラー
};
use crate::visual_sample_world::{目視見本世界のアセットルートを作る, 目視見本世界のシーン名};

/// 積和融合の有無でビンが変わる線形RGB。融合しない計算では相対輝度がちょうど添字74の境界0.18460327になり、
/// 融合する計算では1つ下の単精度へ落ちて添字73のビンへ入る。3成分とも半精度で正確に表せる値であるため、
/// 半精度のHDR中間画像を通ってもこの性質が保たれる(この組の探索と性質はCPU正本の単体試験が固定する)。
const 探り色: &str = "0.062561035,0.19641113,0.42700195";
/// 探り色が入るべきビンの添字。CPU正本の単体試験が同じ値を固定する。
pub(super) const 探り色のビンの添字: &str = "74";

/// 描くフレーム数。`terrain-visual`と同じ本数であり、空と間接照明の焼き上げが定常へ入る状態まで進める。
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(120);

/// 探り色を背景へ流すかどうか。流す条件では空も遠景の霞も外し、背景の画素をクリア色そのものに保つ。
pub(super) enum 探り色の扱い {
    流さない,
    背景へ流す,
}

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoにリリース版を構築させて起動する,
        目視見本世界のアセットルートを作る(),
        出力ディレクトリ,
    )
}

pub(super) fn 描画して報告を読む(
    実行環境: &描画検収の実行環境,
    実行名の綴り: &str,
    一日内秒: &str,
    探り: &探り色の扱い,
) -> Result<自動露出の報告, String> {
    println!("[xtask] auto-exposure描画: {実行名の綴り}");
    let 報告 = 実行環境.書き出させて報告を採る(
        検収の実行名::生成する(実行名の綴り)?,
        &起動指定を組み立てる(一日内秒, 探り),
        書き出しの形式::明るさの圧縮前,
    )?;
    読み解く(報告.本文(), 実行名の綴り)
}

fn 起動指定を組み立てる(一日内秒: &str, 探り: &探り色の扱い) -> アプリの起動指定 {
    let 指定 = アプリの起動指定::シーンと枚数を決める(目視見本世界のシーン名, フレーム数)
        .値を持つ選択肢を足す("--time-of-day", 一日内秒)
        .選択肢を足す("--no-taa")
        .選択肢を足す("--report-auto-exposure");
    match 探り {
        探り色の扱い::流さない => 指定,
        探り色の扱い::背景へ流す => 指定
            .値を持つ選択肢を足す("--auto-exposure-probe", 探り色)
            .選択肢をまとめて足す(&["--no-sky", "--no-aerial-composite"]),
    }
}
