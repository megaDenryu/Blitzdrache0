//! blitz_appが出す自動露出の1行を読み解く工程。受け取るのは終了時報告、返すのはその行が持つ値の組である。
//!
//! 行が1本も無いことを失敗として扱うのは、報告が出なかった実行を「一致した」と読み替えないためである。
//!
//! 値を綴りのまま持つのは、要約が報告の表記をそのまま見せるためである。数として読むのは、
//! 許容を持つ比べを行う目標補正段だけであり、その読み取りは`step_tolerance`が持つ。

use crate::acceptance::{報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

/// 自動露出の報告1行ぶんの値。判定はこの型を読むだけで済む。
pub(super) struct 自動露出の報告 {
    pub(super) ビン一致: bool,
    pub(super) 枠一致: bool,
    pub(super) 最初の食い違いビン: String,
    pub(super) ビンへ入った総数: String,
    pub(super) cpu添字の重み付き総和: String,
    pub(super) gpu添字の重み付き総和: String,
    pub(super) cpu目標補正段: String,
    pub(super) gpu目標補正段: String,
    pub(super) gpu補正段: String,
    pub(super) 初期化済み: bool,
    pub(super) 導出不能フレーム数: String,
    pub(super) 上端到達率: String,
    pub(super) 下端到達率: String,
    pub(super) 探り色のビン: String,
    pub(super) 探り色のcpu件数: String,
    pub(super) 探り色のgpu件数: String,
}

const 行の前置き: 報告の見出し = 報告の見出し::定数から生成する("自動露出行 ");

pub(super) fn 読み解く(報告: &終了時報告) -> Result<自動露出の報告, 検収エラー> {
    let 行 = 報告.見出しの1行(&行の前置き)?;
    Ok(自動露出の報告 {
        ビン一致: 真偽を読む(&行, "ビン一致")?,
        枠一致: 真偽を読む(&行, "枠一致")?,
        最初の食い違いビン: 値を読む(&行, "最初の食い違いビン")?,
        ビンへ入った総数: 値を読む(&行, "ビンへ入った総数")?,
        cpu添字の重み付き総和: 値を読む(&行, "CPU添字の重み付き総和")?,
        gpu添字の重み付き総和: 値を読む(&行, "GPU添字の重み付き総和")?,
        cpu目標補正段: 値を読む(&行, "CPU目標補正段")?,
        gpu目標補正段: 値を読む(&行, "GPU目標補正段")?,
        gpu補正段: 値を読む(&行, "GPU補正段")?,
        初期化済み: 真偽を読む(&行, "初期化済み")?,
        導出不能フレーム数: 値を読む(&行, "導出不能フレーム数")?,
        上端到達率: 値を読む(&行, "上端到達率")?,
        下端到達率: 値を読む(&行, "下端到達率")?,
        探り色のビン: 値を読む(&行, "探り色のビン")?,
        探り色のcpu件数: 値を読む(&行, "探り色のCPU件数")?,
        探り色のgpu件数: 値を読む(&行, "探り色のGPU件数")?,
    })
}

fn 値を読む(行: &報告の行, 鍵: &'static str) -> Result<String, 検収エラー> {
    行.鍵に結ばれた綴り(&報告の行の鍵::定数から生成する(鍵), 鍵に値が結ばれる形::等号の後ろが値である)
}

fn 真偽を読む(行: &報告の行, 鍵: &'static str) -> Result<bool, 検収エラー> {
    行.鍵に結ばれた真偽(&報告の行の鍵::定数から生成する(鍵), 鍵に値が結ばれる形::等号の後ろが値である)
}
