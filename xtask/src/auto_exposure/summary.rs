//! 判定を通った報告から、成功時に出す1行を組む工程。受け取るのは通常の条件と探り色の条件の報告、返すのは要約の文である。
//!
//! 判定と分けるのは、合否を決める規則と読み手へ何を見せるかが別の関心事だからである。
//! 要約が持つのは実測値だけであり、判定の閾値を1つも書かない(閾値は判定側の定数が正本である)。

use super::parse::自動露出の報告;

pub(super) fn 要約を組む(報告: &自動露出の報告, 探り: &自動露出の報告, 出力先: &std::path::Path) -> String {
    format!(
        "validationの指摘0件、CPU正本とGPUの全128ビンと2つの枠が一致(ビンへ入った総数{})、導出の整数の中間値は双方{}でバイト一致、目標補正段はCPU正本{}・GPU{}、追従中の補正段{}で2実行が一致、導出不能フレーム0回、上端到達率{}・下端到達率{}。積和融合の有無でビンが変わる探り色は期待どおり添字{}へ入り、その件数はCPU正本とGPUがともに{}。圧縮前のHDRは{}にある",
        報告.ビンへ入った総数,
        報告.cpu添字の重み付き総和,
        報告.cpu目標補正段,
        報告.gpu目標補正段,
        報告.gpu補正段,
        報告.上端到達率,
        報告.下端到達率,
        探り.探り色のビン,
        探り.探り色のcpu件数,
        出力先.display()
    )
}
