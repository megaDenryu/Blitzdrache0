//! 目標補正段どうしの近さの判定。受け取るのはCPU正本とGPUの10進表記、返すのは合否である。
//!
//! 判定の台帳から分けるのは、この1つの比較だけが許容を持ち、その許容の意味と根拠をここが所有するためである。
//! ヒストグラムの件数と添字の重み付き総和は整数であり、判定側は厳密な一致を見るだけで許容を1つも持たない。

#[cfg(test)]
mod step_tolerance_tests;

use crate::acceptance::{判定の名前, 判定の破れ};

/// 目標補正段に許す食い違い(EV)。整数の中間値が一致した後の、浮動小数の境界ぶんだけの余地である。
/// 2語から実数への変換と合成・除算・1次式にCPUとGPUの差の余地があり、とりわけ単精度の除算はVulkanが厳密な丸めを要求しない。
/// 明るさの比で1.0000069倍であり、絵にも判定にも現れない。
/// 旧値1.0e-6は「実測差が偶然0だった」単一の輝度分布の観測を暗黙の契約にしていた。局所可視性補正が輝度分布を
/// 変えた2026-08-05の実測で、整数の中間値が一致したまま合成誤差1.9073486e-6 EV(単一の最終丸めでなく、
/// 重み付き総和のf32化・除算・後続演算を合わせた観測差)が出たため、その約5.24倍の余裕へ広げた(AgentRoom連番635-636)。
const 許容する段の差: f32 = 1.0e-5;

const CPU正本の目標補正段: 判定の名前 = 判定の名前::定数から生成する("CPU正本の目標補正段");
const GPUの目標補正段: 判定の名前 = 判定の名前::定数から生成する("GPUの目標補正段");
const 段の差: 判定の名前 = 判定の名前::定数から生成する("CPU正本とGPUの目標補正段の差(EV)");

/// 段の差をEVの絶対値で見る。相対で見ないのは、目標が「目標中間灰の対数輝度 - 平均」の引き算であり、
/// 平均の最後の数ビットの食い違いが桁落ちで相対値としては大きく見えるためである。絵に効くのは段の差そのものである。
///
/// 注意: 両方の値と差が有限であることを先に要求する。非数どうしの比較はどの向きでも偽になるため、
/// 差だけを許容と比べると、GPUの目標が非数になった退行が「許容を超えていない」として合格へ落ちる。
pub(super) fn 近さを判定する(正本: &str, 写し: &str) -> Result<(), 判定の破れ> {
    let 左 = 目標補正段を読む(&CPU正本の目標補正段, 正本)?;
    let 右 = 目標補正段を読む(&GPUの目標補正段, 写し)?;
    let 差 = f64::from((左 - 右).abs());
    段の差.有限であることを課す(差)?;
    段の差.上限を課す(差, f64::from(許容する段の差))
}

fn 目標補正段を読む(判定名: &判定の名前, 綴り: &str) -> Result<f32, 判定の破れ> {
    let 値: f32 = 判定名.材料を数として読む(綴り)?;
    判定名.有限であることを課す(f64::from(値))?;
    Ok(値)
}
