//! 順3-Iaの検収入口。遠方環境の立方体画像をvalidation層を有効にしたウィンドウなし実行のGPUで焼いて読み戻し、
//! 鍵の判定・validationの指摘・円盤非二重計上の負の対照・全テクセルの健全性・代表テクセルのCPU正本との一致・
//! 面境界の連続性を判定する。
//!
//! 判定の対象は`blitz_app`の遠方環境報告が出す機械可読な行であり、GPU側の生成シェーダーとCPU側の正本が
//! 同じ式であることを見る。シェーダーがCPU正本からずれる欠陥は、この検査だけが捉えられる
//! (ユニットテストはCPU側しか見ない)。
//! 参照: `_doc/設計/放射輝度問い合わせ階層.md`「検収(機械判定)」

mod judgment;
pub(crate) mod parse;
mod thresholds;

use std::process::ExitCode;

use crate::acceptance::{
    アプリの起こし方, 世界を読まずに報告を採る実行環境, 検収の実行名, 検収エラー, 終了時報告
};

/// この実行を指す名前。絵は書き出さないが、失敗の文面がどの実行かを名指すために要る。
const 遠方環境の実行名: 検収の実行名 = 検収の実行名::定数から生成する("distant_environment");

pub fn 遠方環境画像の生成を確認する() -> ExitCode {
    match 検収する() {
        Ok(要約) => {
            println!("[xtask] distant-environment成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] distant-environment失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

fn 検収する() -> Result<String, 検収エラー> {
    let 出力 = 報告を採る()?;
    let 報告 = parse::報告を取り出す(&出力).inspect_err(|_| 出力.標準エラーを画面へ流す())?;
    let 判定 = judgment::全項目を検査する(&報告).inspect_err(|_| 出力.標準エラーを画面へ流す())?;
    表を出す(&報告);
    Ok(format!(
        "鍵の判定が{}条件すべて期待どおりで、太陽円盤放射輝度だけを変えた対がバイト一致し、全{}テクセルが有限かつ非負で、代表{}テクセルがCPU正本と一致し(最大相対誤差{:.3e})、面境界の最大相対差が{:.3e}だった。{}",
        報告.鍵一覧.len(),
        報告.テクセル数,
        判定.代表テクセル数,
        判定.最大相対誤差,
        報告.面境界の最大相対差,
        判定.検証の告知
    ))
}

/// 判定の根拠になった数を人が読める形で並べる。判定そのものは`judgment`が済ませている。
fn 表を出す(報告: &parse::報告) {
    println!("遠方環境の読み戻し:");
    println!(
        "  テクセル数: {} (非有限{} 負{} 予約が非零{})",
        報告.テクセル数, 報告.非有限, 報告.負, 報告.予約が非零
    );
    println!("  円盤対照の不一致: {}", 報告.円盤対照の不一致);
    println!("  面境界の最大相対差: {:.3e}", 報告.面境界の最大相対差);
    for 行 in &報告.鍵一覧 {
        println!("  鍵 {}: {}", 行.条件, 行.指示);
    }
}

/// 遠方環境を焼かせて報告を採る。validationの指摘は判定の一部としてこの入口が読むため、
/// 実行環境が零件を確かめる口は通さない。
fn 報告を採る() -> Result<終了時報告, 検収エラー> {
    println!("[xtask] blitz_appの遠方環境報告を実行");
    let 実行環境 = 世界を読まずに報告を採る実行環境::作る(アプリの起こし方::毎回cargoに構築させて起動する);
    実行環境.報告を採る(遠方環境の実行名, &["--report-distant-environment"])
}
