//! 由来から注記の並びを作る段の検査。gitも実行ファイルも読まず、値を組み立ててから答えだけを見る。
//!
//! 未追跡を2件置く場合を検査の中心にするのは、1件だけでは「1件目しか出さない実装」が通ってしまうためである。
//! 実際に、費用計測の入口の書き出しが注記の1行目しか書かない状態になり、成果物から未追跡のパスが落ちた。
//!
//! 件数の語も同じ組で見る。有無だけの語では、既知の保全ファイル1件と多数の生成物を読み分けられない。

use super::差分の有無;
use super::構築の由来;

fn 由来を組む(未追跡: 差分の有無, パス一覧: &[&str]) -> 構築の由来 {
    構築の由来 {
        基準コミット: "abc1234".to_string(),
        追跡済みの変更: 差分の有無::無し,
        未追跡のファイル: 未追跡,
        未追跡のパス一覧: パス一覧.iter().map(|パス| (*パス).to_string()).collect(),
        実行ファイルの更新時刻: "1785945938".to_string(),
        実行ファイルのバイト数: 5_510_144,
    }
}

/// 未追跡が2件あるとき、注記が由来の1行とパス2行の順に並ぶ。
#[test]
fn 未追跡が2件なら注記は3件になり順序を保つ() {
    let 由来 = 由来を組む(差分の有無::有り, &["保全メモ.txt", "xtask/src/生成物.rs"]);
    let 注記 = 由来.注記一覧();
    assert_eq!(注記.len(), 3);
    assert!(注記[0].starts_with("計測に使ったバイナリ "), "{}", 注記[0]);
    assert_eq!(注記[1], "未追跡ファイル 保全メモ.txt");
    assert_eq!(注記[2], "未追跡ファイル xtask/src/生成物.rs");
}

/// 由来の行は未追跡の件数を添える。件数が無いと、1件の保全ファイルと多数の生成物が同じ語になる。
#[test]
fn 由来の行は未追跡の件数を添える() {
    let 由来 = 由来を組む(差分の有無::有り, &["a.txt", "b.txt"]);
    assert!(由来.一行にする().contains("未追跡=あり(2件)"), "{}", 由来.一行にする());
}

/// 未追跡が無ければ注記は由来の1行だけである。
#[test]
fn 未追跡が無ければ注記は1件になる() {
    let 由来 = 由来を組む(差分の有無::無し, &[]);
    assert_eq!(由来.注記一覧().len(), 1);
    assert!(由来.一行にする().contains("未追跡=なし"), "{}", 由来.一行にする());
}

/// gitを読めなかった実行は「なし」と同じ語にしない。確かめられなかったことを確かめた結果として残さない。
#[test]
fn 読めなかった実行は無しと同じ語にならない() {
    let 由来 = 由来を組む(差分の有無::読めない, &[]);
    assert!(由来.一行にする().contains("未追跡=読めない"), "{}", 由来.一行にする());
}
