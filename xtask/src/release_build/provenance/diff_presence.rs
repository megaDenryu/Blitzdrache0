//! 作業ツリーにその種類の差分が在るかどうかという3状態の値。触れる状態を持たず、担うのはgitの出力を
//! 「在る・無い・読めない」の3つへ写すことと、その語を1つに決めることだけである。
//!
//! 真偽値で持たないのは、gitを読めなかったときに「差分が無い」と「確かめられなかった」が同じ値になるためである。
//! 由来の行は後日ほかの人が読む記録であり、確かめられなかったことを確かめた結果として残してはならない。

/// その種類の差分の有無。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 差分の有無 {
    有り,
    無し,
    読めない,
}

impl 差分の有無 {
    /// gitの標準出力から決める。出力が空なら差分は無く、行が1つでもあれば在る。
    /// 呼び出しそのものが失敗していたら読めなかったこととして残す。
    pub(super) fn gitの出力から決める(出力: Option<String>) -> Self {
        match 出力 {
            Some(出力) if 出力.is_empty() => Self::無し,
            Some(_) => Self::有り,
            None => Self::読めない,
        }
    }

    pub(super) fn 語(self) -> &'static str {
        match self {
            Self::有り => "あり",
            Self::無し => "なし",
            Self::読めない => "読めない",
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 空の出力は差分なしで行があれば差分ありになる() {
        assert_eq!(差分の有無::gitの出力から決める(Some(String::new())), 差分の有無::無し);
        assert_eq!(差分の有無::gitの出力から決める(Some(" M a.rs".to_string())), 差分の有無::有り);
    }

    /// 読めなかったことを「差分なし」へ倒さない。倒すと、確かめられなかった実行が確かめた実行と同じ語で残る。
    #[test]
    fn 読めなかったときは差分なしへ倒さない() {
        assert_eq!(差分の有無::gitの出力から決める(None), 差分の有無::読めない);
        assert_eq!(差分の有無::読めない.語(), "読めない");
    }
}
