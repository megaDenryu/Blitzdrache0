//! 計測の生値を書き出すファイル。名前を私有し、出力ディレクトリと結んだ置き場所だけを外へ出す。
//!
//! 入口ごとに出力ディレクトリは違うが、その中の生値の名前は共通である。名前を配ると入口ごとに
//! 綴りを持ち直すことになり、書く側と読む側で片方だけが古い名前を指す形が生まれる。

use std::path::{Path, PathBuf};

pub struct 計測の生値のファイル;

impl 計測の生値のファイル {
    const 名前: &'static str = "raw.tsv";

    /// その入口の出力ディレクトリの中での置き場所。生のパスを組むのはこの1箇所である。
    pub fn 出力ディレクトリの中の場所(出力ディレクトリ: &Path) -> PathBuf {
        出力ディレクトリ.join(Self::名前)
    }
}
