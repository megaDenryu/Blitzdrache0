//! 構築した実行ファイルの由来。担当するのは、計測に使ったバイナリがどの基準から作られたかを1行で言える形に
//! まとめることだけである。計測の値も条件も知らない。
//!
//! これが要るのは、計測の成果物だけを見ても「どの版で測ったか」が後から分からないためである。値と版が結び
//! 付いていないと、ある実装状態で正しく採った値を、後になって別の実装状態の値として読んでしまう。
//! 2026-08-05に採った深度プリパスの計測は当時の最新実装での正当な値だったが、成果物に版が無かったために
//! 翌日の実装状態の値と取り違えられた。**閉じるべき欠陥は誤帰属であって、構築の抜けではない。**
//!
//! **記録するのは基準コミットと、そこからの変更の有無である。版の証明ではない。** 追跡済みの変更が「あり」の
//! 実行では、基準コミットから何がどう変わったバイナリなのかをこの行から復元できず、版は一意に定まらない。
//! この行が言えるのは「基準はこのコミットであり、そこから動いているかどうか」までである。
//!
//! **追跡済みの変更と未追跡のファイルを分けて記録する。** 1つの真偽値に畳むと、構築入力に1つも関わらない
//! 未追跡のファイルが置いてあるだけで常に「変更あり」になり、由来を後日読む人が本当に構築入力が動いていたのかを
//! 判別できない。公式値として採用してよいのは追跡済みの変更が「なし」の実行だけである。
//!
//! **未追跡が在る実行は、そのパスの一覧も成果物へ残す。** 未追跡のファイルが構築や実行の入力に入らないことは
//! gitからは決められない。build.rsが走査する先・シェーダーやアセットの検索先・追跡済みのコードが固定の名前で
//! 読む生成物は、未追跡のままでも入力になる。有無だけを残すと、後日その成果物を読む人が「既知の保全ファイル
//! だったのか、それとも入力だったのか」を判別できない。パスを残せば読む人が自分で確かめられる。
//! ファイルの中身は1つも読まない。残すのは名前だけである。
//!
//! **更新時刻を鮮度の証明に使ってはならない。** cargoは入力が変わらなければ構築を省くため、正しく最新の
//! バイナリであっても更新時刻は前の構築のままになる。古い更新時刻は「構築が効いていない」ことを意味しない。
//! 更新時刻とバイト数は、同じコミットの中で別々に構築した実行ファイルを見分けるための識別の補助である。
//! ハッシュでなくこの2つにするのは、リリースの実行ファイルが数十メガバイトあり、計測のたびに全体を読み直す
//! 費用に見合わないためである。識別の補助という位置づけにはこの粒度で足りる。

mod capture;
mod diff_presence;
#[cfg(test)]
mod notes_tests;

use std::path::Path;

use diff_presence::差分の有無;

/// 計測に使った実行ファイルの出どころ。
pub struct 構築の由来 {
    基準コミット: String,
    追跡済みの変更: 差分の有無,
    未追跡のファイル: 差分の有無,
    /// 未追跡のファイルのパス。読めなかった実行と1件も無い実行ではどちらも空である(その別は上の枝が持つ)。
    未追跡のパス一覧: Vec<String>,
    実行ファイルの更新時刻: String,
    実行ファイルのバイト数: u64,
}

impl 構築の由来 {
    /// 構築の直後に採る。gitが読めない環境でも計測は止めず、読めなかったことを値として残す。
    pub fn 採る(実行ファイル: &Path) -> Self {
        let (更新時刻, バイト数) = capture::実行ファイルの状態(実行ファイル);
        let 未追跡の出力 = capture::gitの出力("ls-files", &["--others", "--exclude-standard"]);
        Self {
            基準コミット: capture::gitの出力("rev-parse", &["--short", "HEAD"]).unwrap_or_else(|| "読めない".to_string()),
            追跡済みの変更: 差分の有無::gitの出力から決める(
                capture::gitの出力("status", &["--porcelain", "--untracked-files=no"]),
            ),
            未追跡のファイル: 差分の有無::gitの出力から決める(未追跡の出力.clone()),
            未追跡のパス一覧: capture::行ごとのパス(未追跡の出力.as_ref()),
            実行ファイルの更新時刻: 更新時刻,
            実行ファイルのバイト数: バイト数,
        }
    }

    /// ログとtsvへ同じ綴りで残す1行。どの基準から作ったバイナリで測ったかの確認がこの行だけで閉じる。
    pub fn 一行にする(&self) -> String {
        format!(
            "基準コミット={} 追跡済みの変更={} 未追跡={} 実行ファイルの更新時刻={} バイト数={}",
            self.基準コミット,
            self.追跡済みの変更.語(),
            self.未追跡の語(),
            self.実行ファイルの更新時刻,
            self.実行ファイルのバイト数
        )
    }

    /// 成果物の先頭とログへ残す注記の並び。1行目が由来そのもので、未追跡が在れば2行目以降がそのパスである。
    /// パスを1行1件にするのは、名前に空白を含むファイルでも区切りが曖昧にならないためである。
    pub fn 注記一覧(&self) -> Vec<String> {
        let mut 一覧 = vec![format!("計測に使ったバイナリ {}", self.一行にする())];
        for パス in &self.未追跡のパス一覧 {
            一覧.push(format!("未追跡ファイル {パス}"));
        }
        一覧
    }

    /// 未追跡の語。在るときは件数を添える。件数だけでも、既知の保全ファイル1件と多数の生成物を読み分けられる。
    fn 未追跡の語(&self) -> String {
        match self.未追跡のファイル {
            差分の有無::有り => format!("あり({}件)", self.未追跡のパス一覧.len()),
            その他 => その他.語().to_string(),
        }
    }
}
