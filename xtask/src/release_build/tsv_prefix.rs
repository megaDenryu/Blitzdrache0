//! 由来の注記の並びを、tsvの見出しより前へ置く前置きへ整形する純関数。触れる状態を持たず、gitも実行ファイルも
//! 読まない。担当するのは、井桁と改行の付け方という1つの規約だけである。
//!
//! **整形を1つに集めるのは、同じ責務が入口ごとに複製されるのを止めるためである。** 実際に、費用計測の2つの
//! 入口がそれぞれ前置きを組んでいた時期に、片方だけが注記の1行目しか書かない状態になり、その入口の成果物
//! からだけ未追跡ファイルのパスが落ちた。整形が1つなら、片方だけが古い形のまま残ることが起こらない。
//!
//! 引数を注記の並びにして`構築の由来`にしないのは、この工程を検査するのにgitも実行ファイルも要らない形へ
//! 落とすためである。前置きの規約が壊れたかどうかは、注記の並びと出来上がった文字列だけで決まる。

/// 注記1件につき1行を作り、井桁と空白で始めて改行で閉じる。並びの順はそのまま保つ。
///
/// 井桁で始めるのは、表を読む道具が見出しより前の行を注記として飛ばせる形に揃えるためである。
/// 1行1件にするのは、名前に空白を含むファイルのパスでも区切りが曖昧にならないためである。
pub fn tsvの前置き(注記一覧: &[String]) -> String {
    注記一覧.iter().map(|注記| format!("# {注記}\n")).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn 語一覧(一覧: [&str; 3]) -> Vec<String> {
        一覧.iter().map(|語| (*語).to_string()).collect()
    }

    /// 2件以上を渡したときに全件が出ることと、並びが入れ替わらないことを固定する。
    /// 1行目だけを書く実装と、順序を保たない実装の両方がこの検査で落ちる。
    #[test]
    fn 全件へ井桁と改行を付けて順序を保つ() {
        let 前置き = tsvの前置き(&語一覧([
            "計測に使ったバイナリ 基準コミット=abc",
            "未追跡ファイル a.txt",
            "未追跡ファイル b/c.txt",
        ]));
        assert_eq!(
            前置き,
            "# 計測に使ったバイナリ 基準コミット=abc\n# 未追跡ファイル a.txt\n# 未追跡ファイル b/c.txt\n"
        );
        assert_eq!(前置き.lines().count(), 3);
        assert!(前置き.lines().all(|行| 行.starts_with("# ")), "井桁で始まらない行がある: {前置き}");
    }

    /// 空白を含むパスが1行に収まることを見る。区切りを空白にした実装はこの検査で落ちる。
    #[test]
    fn 空白を含むパスも1行に収まる() {
        let 前置き = tsvの前置き(&["未追跡ファイル 保 全 メモ.txt".to_string()]);
        assert_eq!(前置き, "# 未追跡ファイル 保 全 メモ.txt\n");
        assert_eq!(前置き.lines().count(), 1);
    }

    /// 注記が1件も無ければ前置きも空である。空行を1つ置く実装は、見出しの前に意味の無い行を残す。
    #[test]
    fn 注記が無ければ前置きは空になる() {
        assert_eq!(tsvの前置き(&[]), "");
    }
}
