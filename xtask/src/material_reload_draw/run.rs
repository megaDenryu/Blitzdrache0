//! 差し替えを挟む1回の起動の指定と、その起動が書き出す2枚の名前。受け取るのは無く、返すのは実行環境へ渡す
//! 起動指定である。起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! 起動が1回なのがこの検収の要点である。アプリ自身が計画にしたがって差し替え前の絵を`_before`の名前で書き出し、
//! 実行時アセットを上書きし、最終フレームで差し替え後の絵を書き出す。2回起動すると、同じプロセスの中で世代が
//! 切り替わったことを見たことにならない。
//! ライティングとポスト処理を切るのは、板の画素を材質のベースカラーそのものとして読み取るためである。
//! 光の当たり方や光のにじみが混ざると、色の違いが材質の違いによるものか決められない。

use std::path::PathBuf;

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収の実行名, 検収エラー, 検収シーン名,
};

const アセットルート: &str = "target/runtime_assets";
/// ホットリロードの0.5秒ごとの確認と再読込を待つため、既存の材質境界の検収より長く回す。
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(300);
const 起動の選択肢: [&str; 4] = ["--unlit", "--no-post", "--report-draw-issue", "--report-memory"];
const シーンの綴り: &str = "material_reload";
const シーン名: 検収シーン名 = 検収シーン名::生成する(シーンの綴り);

/// 最終フレームの書き出しの基準名。アプリはこの名前をそのまま使う。
pub(super) const 差し替え後の実行名: 検収の実行名 = 検収の実行名::定数から生成する(シーンの綴り);
/// 差し替え前の書き出しの基準名。アプリが最終フレームの名前へ`_before`を足して書き出す。
/// 綴りをここで組むのは、書く側と読む側の食い違いが「ファイルが無い」という遠い失敗に化けるためである。
pub(super) const 差し替え前の実行名: 検収の実行名 = 検収の実行名::定数から生成する("material_reload_before");

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::綴りから生成する(アセットルート),
        出力ディレクトリ,
    )
}

pub(super) fn 起動指定を組み立てる() -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数).選択肢をまとめて足す(&起動の選択肢)
}
