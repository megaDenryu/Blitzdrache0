//! 差し替えの前後の画素の判定。受け取るのは2枚の読み戻し画像、返すのは合否と実測の要約である。
//!
//! 判定は2段である。まず左右それぞれで差し替えの前後の色が十分に離れていることを見て、世代が本当に切り替わったことを確かめる。
//! 次にどちらの絵にも相手の世代の色を持つ画素が1つも無いことを数える。材質レコードと画像集合が1つの世代として
//! 原子的に切り替わらなければ、同じ絵の中に旧世代の色と新世代の色が同時に現れる。

use crate::acceptance::読み戻し画像;
use crate::plate_region::{代表色, 左右の代表色を採る};

/// 差し替えの前後の色が別の材質だと言えるための、対応する成分の差の最大の下限。
/// ベースカラー係数の差はこれよりはるかに大きいため、この下限は「わずかな陰影の違い」と「別の材質」を分ける値として置く。
const 成分差の下限: u64 = 40;

pub(super) fn 差し替えの画素を検査する(前: &読み戻し画像, 後: &読み戻し画像) -> Result<String, String> {
    let 前の色 = 左右の代表色を採る(前)?;
    let 後の色 = 左右の代表色を採る(後)?;
    離れていることを確かめる("左", 前の色.左, 後の色.左)?;
    離れていることを確かめる("右", 前の色.右, 後の色.右)?;

    let 旧世代の色 = [前の色.左, 前の色.右];
    let 新世代の色 = [後の色.左, 後の色.右];
    let 差し替え前の自世代 = 混成が無いことを確かめる("差し替え前", 前, &旧世代の色, &新世代の色)?;
    let 差し替え後の自世代 = 混成が無いことを確かめる("差し替え後", 後, &新世代の色, &旧世代の色)?;
    Ok(format!(
        "差し替え前の代表色は左{:?}・右{:?}、差し替え後は左{:?}・右{:?}、自世代の色を持つ画素は差し替え前{差し替え前の自世代}個と差し替え後{差し替え後の自世代}個、相手の世代の色を持つ画素はどちらも0個",
        前の色.左, 前の色.右, 後の色.左, 後の色.右
    ))
}

fn 離れていることを確かめる(位置: &str, 前: 代表色, 後: 代表色) -> Result<(), String> {
    let 差 = 前.成分差の最大(後);
    if 差 < 成分差の下限 {
        return Err(format!(
            "{位置}の板の色が差し替えの前後で変わっていない: 前{前:?}、後{後:?}、成分差の最大{差}(下限{成分差の下限})"
        ));
    }
    Ok(())
}

/// その絵の中で自世代の色を持つ画素を数え、相手の世代の色を持つ画素が1つも無いことを確かめる。
/// 自世代の色が1つも無ければ、板そのものが描かれていないため判定の材料が無い。
fn 混成が無いことを確かめる(
    名前: &str, 画像: &読み戻し画像, 自世代の色: &[代表色], 相手の世代の色: &[代表色]
) -> Result<u64, String> {
    let 自世代 = 数える(画像, 自世代の色);
    let 相手の世代 = 数える(画像, 相手の世代の色);
    if 自世代 == 0 {
        return Err(format!("{名前}の絵に自分の世代の色{自世代の色:?}を持つ画素が1つも無い"));
    }
    if 相手の世代 != 0 {
        return Err(format!(
            "{名前}の絵に相手の世代の色{相手の世代の色:?}を持つ画素が{相手の世代}個ある(旧世代と新世代が混ざっている)"
        ));
    }
    Ok(自世代)
}

fn 数える(画像: &読み戻し画像, 色一覧: &[代表色]) -> u64 {
    let mut 件数 = 0u64;
    for 画素 in 画像.画素列() {
        if 色一覧.iter().any(|色| 色.画素が一致するか(画素)) {
            件数 += 1;
        }
    }
    件数
}
