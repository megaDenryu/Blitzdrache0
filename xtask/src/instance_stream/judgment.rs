//! ストリーミング統合の検収の判定。実行どうしの数を突き合わせる比較そのものをここが所有し、
//! 何と何を突き合わせるかは2つの子が持つ。`lifecycle`は束の出入りと解除後の残留を、`invariance`は
//! 段と可視の変動が資源を動かさないことと各実行が満たすべき上限を見る。

mod invariance;
mod lifecycle;

pub(super) use invariance::{
    可視の変動が資源を動かさないことを検査する, 実行ごとの上限を検査する, 段が実際に変わることを検査する
};
pub(super) use lifecycle::{束が出入りすることを検査する, 残留がないことを検査する};

use crate::acceptance::{判定の名前, 判定の破れ};

/// 常駐する25チャンク。台帳と可視材料の期待値をこの数から決める。
const 常駐チャンク数: u64 = 25;

fn 実行どうしで同じ数であることを課す(
    項目名: &str, 左の名: &str, 左: u64, 右の名: &str, 右: u64
) -> Result<(), 判定の破れ> {
    let 判定名 = 判定の名前::組み立てた綴りから生成する(format!("{左の名}の実行の{項目名}({右の名}の実行と一致するはずである)"));
    判定名.一致を課す(左, 右)
}

fn 実行の数が期待どおりであることを課す(項目名: &str, 実行名: &str, 実測: u64, 期待: u64) -> Result<(), 判定の破れ> {
    判定の名前::組み立てた綴りから生成する(format!("{実行名}の実行の{項目名}")).一致を課す(実測, 期待)
}
