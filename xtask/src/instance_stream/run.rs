//! 地形と植生が同居する25チャンク世界を1回走らせる工程。受け取るのは実行環境と名前とフレーム数と追加の選択肢、
//! 返すのは終了時報告の2種の読み取り結果と最終フレームの読み戻し画像である。
//! 監視対象シェーダーへリポジトリ本体でなく一時コピーを渡すのは、スモーク計画の書き換えがリポジトリのファイルを変えないようにするためである。
//! 時間再構成は`--no-taa`で外す。この入口の判定がバイト一致に依るため、フレームをまたぐ混合が入ると前のフレームの残りが絵に混ざる。

use std::path::{Path, PathBuf};

use super::error::植生ストリーミング統合の検収エラー;
use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収の実行名, 検収エラー, 検収シーン名,
    読み戻し画像,
};
use crate::report_parse::計数報告;
use crate::streaming_report::ストリーミング要約報告;

/// 検証用地形世界の実行時アセットの置き場。`compile-assets`の地形世界の既定出力ルートと同じ値である。
const アセットルート: &str = "target/terrain_assets";

/// 起動時シーン。レンダラーはチャンクが1つも常駐しない期間にも描画対象を要求するため、束ID0を占めるこの対象が要る。
const 起動時シーン: 検収シーン名 = 検収シーン名::生成する("terrain_origin");

/// RAMとVRAMの上限。地形と植生が同居した25チャンクの実測に対して余裕を持つ値であり、この検収は縮退を見ない。
const 上限バイト数: &str = "16777216";
const 先読み半径: &str = "2";

/// ライティングを止めるのは、この検収が植生の画素を地形の画素とベースカラーの色だけで見分けるためである。
/// ポスト処理も止めるのは、明るさの圧縮が色を移して同じ見分けを鈍らせるためである。
/// 空を止めるのは、地形世界が空を持つ方針であり、空が塗った画素を番兵背景と見分けられなくなるためである。
const 共通の選択肢: [&str; 8] = [
    "--streaming",
    "--instance-stream-route",
    "--report-streaming-summary",
    "--report-memory",
    "--report-draw-issue",
    "--unlit",
    "--no-sky",
    "--no-post",
];

pub(super) struct 実行 {
    pub(super) 名前: String,
    pub(super) 計数: 計数報告,
    pub(super) 要約: ストリーミング要約報告,
    pub(super) 画像: 読み戻し画像,
}

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::綴りから生成する(アセットルート),
        出力ディレクトリ,
    )
}

pub(super) fn 走らせる(
    実行環境: &描画検収の実行環境,
    名前: &str,
    シェーダー入口: &Path,
    フレーム数: 描画フレーム数,
    追加の選択肢: &[&str],
) -> Result<実行, 植生ストリーミング統合の検収エラー> {
    let 実行結果 = 実行環境.描いて読み戻す(
        検収の実行名::生成する(名前)?,
        &起動指定を組み立てる(フレーム数, シェーダー入口, 追加の選択肢),
    )?;
    実行結果.報告().画面へ流す();
    let 要約 = crate::streaming_report::取り出す(実行結果.報告())?;
    Ok(実行 {
        名前: 名前.to_string(),
        計数: crate::report_parse::取り出す(実行結果.報告())?,
        要約,
        画像: 実行結果.画像を取り出す(),
    })
}

fn 起動指定を組み立てる(
    フレーム数: 描画フレーム数, シェーダー入口: &Path, 追加の選択肢: &[&str]
) -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(起動時シーン, フレーム数)
        .選択肢をまとめて足す(&共通の選択肢)
        .値を持つ選択肢を足す("--streaming-preload-radius", 先読み半径)
        .選択肢を足す("--no-taa")
        .値を持つ選択肢を足す("--streaming-ram-limit", 上限バイト数)
        .値を持つ選択肢を足す("--streaming-vram-limit", 上限バイト数)
        .選択肢をまとめて足す(追加の選択肢)
        .パスを値に持つ選択肢を足す("--shader-source", シェーダー入口)
}
