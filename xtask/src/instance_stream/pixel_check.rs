//! 最終フレームの読み戻し画像で、植生が地形の描かれる領域の外へ逸脱していないことを検知する工程。
//! 受け取るのは画像とその実行の可視個体数、返すのは植生画素の数である。画素の色を3種へ見分けるのは`color`が持つ。
//!
//! 判定するのは、各列で最も下にある植生の画素から真下へ下ったとき、番兵背景より先に地形へ当たることである。
//! 地形より先に背景へ当たる列があれば、その列の植生は地形の外にある。
//!
//! 注意: これは接地の証明ではない。個体の背後には常に地形が写るため、個体の高さが地表から数メートルずれていても
//! この判定は通る。接地そのもの、すなわち個体のYが実描画面の三角形と一致することは
//! `crates/blitz_asset_compiler/src/terrain/terrain_tests/ground_height_surface.rs`が焼いた面と突き合わせて確かめる。
//! 走査を列ごとに最も下の植生画素へ限るのは、個体の輪郭がY軸回転で六角形になり、その上辺の画素から真下へ下ると
//! 個体の胴を外れて空へ抜ける列があるためである。そこまで判定に含めると、地形の上にある個体でも不合格になる。

mod color;

use crate::acceptance::{判定の名前, 判定の破れ, 画素の横位置, 画素の縦位置, 読み戻し画像};

pub(super) fn 地形の外への逸脱がないことを検査する(
    画像: &読み戻し画像, 可視個体数: u64
) -> Result<u64, 判定の破れ> {
    let 植生画素数 = 数える(画像, color::植生か);
    // 可視と判じた個体が1体あたり平均1画素も覆っていなければ、群が描かれていないか画面の外にある。
    植生の画素数の判定名(可視個体数).下限を課す(植生画素数, 可視個体数)?;
    for x in 0..画像.幅().画素数() {
        let Some(最下) = 列の最下の植生画素(画像, x) else {
            continue;
        };
        列の植生が地形の上にあることの判定名(x, 最下).真であることを課す(地形へ先に当たるか(画像, x, 最下))?;
    }
    Ok(植生画素数)
}

fn 植生の画素数の判定名(可視個体数: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "植生の画素数(可視と判じた個体{可視個体数}体が1体あたり平均1画素は覆うはずである)"
    ))
}

fn 列の植生が地形の上にあることの判定名(x: usize, 最下: usize) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "列{x}の植生が地形の上にあること(最下の植生の行{最下}の下で番兵背景より先に地形へ当たること)"
    ))
}

/// 最下の植生画素から真下へ下り、地形へ当たれば真、番兵背景へ先に当たれば偽、どちらにも当たらず下端へ抜けたら真とする。
/// 下端へ抜けた列を真とするのは、その列に地形の上か外かを決める材料が写っていないためである。
fn 地形へ先に当たるか(画像: &読み戻し画像, x: usize, 最下: usize) -> bool {
    for y in 最下 + 1..画像.高さ().画素数() {
        let 色 = 画像.座標の画素(画素の横位置::生成する(x), 画素の縦位置::生成する(y));
        if color::地形か(色) {
            return true;
        }
        if color::背景か(色) {
            return false;
        }
    }
    true
}

fn 列の最下の植生画素(画像: &読み戻し画像, x: usize) -> Option<usize> {
    (0..画像.高さ().画素数())
        .rev()
        .find(|y| color::植生か(画像.座標の画素(画素の横位置::生成する(x), 画素の縦位置::生成する(*y))))
}

fn 数える(画像: &読み戻し画像, 判別: fn([u8; 3]) -> bool) -> u64 {
    let mut 件数 = 0_u64;
    for 縦 in 画像.高さ().位置一覧() {
        for 横 in 画像.幅().位置一覧() {
            if 判別(画像.座標の画素(横, 縦)) {
                件数 += 1;
            }
        }
    }
    件数
}
