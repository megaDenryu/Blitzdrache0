//! 最終フレームの読み戻し画像で、植生が地形の描かれる領域の外へ逸脱していないことを検知する工程。
//! 受け取るのは画像とその実行の可視個体数、返すのは植生画素の数である。
//!
//! 画素の種類はベースカラーで見分ける。ライティングもポスト処理も止めた実行であるため、地形は白、同居植生は緑、
//! 何も描かれない画素は番兵背景色になる。判定するのは、各列で最も下にある植生の画素から真下へ下ったとき、
//! 番兵背景より先に地形へ当たることである。地形より先に背景へ当たる列があれば、その列の植生は地形の外にある。
//!
//! 注意: これは接地の証明ではない。個体の背後には常に地形が写るため、個体の高さが地表から数メートルずれていても
//! この判定は通る。接地そのもの、すなわち個体のYが実描画面の三角形と一致することは
//! `crates/blitz_asset_compiler/src/terrain/terrain_tests/ground_height_surface.rs`が焼いた面と突き合わせて確かめる。
//! 走査を列ごとに最も下の植生画素へ限るのは、個体の輪郭がY軸回転で六角形になり、その上辺の画素から真下へ下ると
//! 個体の胴を外れて空へ抜ける列があるためである。そこまで判定に含めると、地形の上にある個体でも不合格になる。

use crate::acceptance::読み戻し画像;

/// 何も描かれない画素の色。`crates/blitz_render`のクリア色であり、`xtask/src/lod_crack/image_check.rs`と同じ値である。
const 番兵背景RGB: [u8; 3] = [63, 75, 97];

/// 番兵背景と認める各成分のずれ幅。多重標本の縁で混ざった画素を背景と誤って数えないため、狭く取る。
const 背景の許容差: i32 = 8;

/// 緑が他の2成分をこれだけ上回る画素を植生とみなす。地形は白(3成分が等しい)、背景は青寄りであるため、この差で3種が分かれる。
const 緑優位の差: i32 = 12;

/// 地形と認める明るさの下限。地形のベースカラーは白であり、同居植生の緑や番兵背景はこの明るさに届かない。
const 地形の明るさ下限: u8 = 180;

/// 地形と認める成分間のずれの上限。白は3成分が等しく、緑の植生はここで落ちる。
const 地形の無彩色許容差: i32 = 30;

pub(super) fn 地形の外への逸脱がないことを検査する(画像: &読み戻し画像, 可視個体数: u64) -> Result<u64, String> {
    let 植生画素数 = 数える(画像, 植生か);
    // 可視と判じた個体が1体あたり平均1画素も覆っていなければ、群が描かれていないか画面の外にある。
    if 植生画素数 < 可視個体数 {
        return Err(format!("植生の画素が{植生画素数}しかない。可視と判じた個体は{可視個体数}体である"));
    }
    for x in 0..画像.幅() {
        let Some(最下) = 列の最下の植生画素(画像, x) else {
            continue;
        };
        判定する(画像, x, 最下)?;
    }
    Ok(植生画素数)
}

/// 最下の植生画素から真下へ下り、地形へ当たれば合格、番兵背景へ先に当たれば不合格、どちらにも当たらず下端へ抜けたら判定しない。
fn 判定する(画像: &読み戻し画像, x: usize, 最下: usize) -> Result<(), String> {
    for y in 最下 + 1..画像.高さ() {
        let 色 = 画像.座標の画素(x, y);
        if 地形か(色) {
            return Ok(());
        }
        if 背景か(色) {
            return Err(format!(
                "列{x}の植生が地形の外へ逸脱している: 最下の植生の行{最下}の下で地形より先に番兵背景へ当たった"
            ));
        }
    }
    Ok(())
}

fn 列の最下の植生画素(画像: &読み戻し画像, x: usize) -> Option<usize> {
    (0..画像.高さ()).rev().find(|y| 植生か(画像.座標の画素(x, *y)))
}

fn 数える(画像: &読み戻し画像, 判別: fn([u8; 3]) -> bool) -> u64 {
    let mut 件数 = 0_u64;
    for y in 0..画像.高さ() {
        for x in 0..画像.幅() {
            if 判別(画像.座標の画素(x, y)) {
                件数 += 1;
            }
        }
    }
    件数
}

fn 植生か(色: [u8; 3]) -> bool {
    let [赤, 緑, 青] = 色.map(i32::from);
    緑 - 赤 > 緑優位の差 && 緑 - 青 > 緑優位の差
}

fn 地形か(色: [u8; 3]) -> bool {
    let [赤, 緑, 青] = 色.map(i32::from);
    let 最大 = 赤.max(緑).max(青);
    let 最小 = 赤.min(緑).min(青);
    色.iter().all(|成分| *成分 >= 地形の明るさ下限) && 最大 - 最小 <= 地形の無彩色許容差
}

fn 背景か(色: [u8; 3]) -> bool {
    色.iter()
        .zip(番兵背景RGB)
        .all(|(成分, 期待)| (i32::from(*成分) - i32::from(期待)).abs() <= 背景の許容差)
}
