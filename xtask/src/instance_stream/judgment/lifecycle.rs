//! 束の寿命についての判定。担当するのは、往復する実行と静止だけの実行の2つを突き合わせて、
//! 束の追加と解除が実際に起きたことと、解除と再読込を経た終状態が静止だけの実行と同じであることを見ることである。

use super::super::run::実行;
use super::{実行どうしで同じ数であることを課す, 実行の数が期待どおりであることを課す, 常駐チャンク数};
use crate::acceptance::{判定の名前, 判定の破れ};

const 往復の実行で起きた束の解除: 判定の名前 = 判定の名前::定数から生成する("往復の実行で起きた束の解除");

pub(in super::super) fn 束が出入りすることを検査する(往復: &実行, 静止: &実行) -> Result<(), 判定の破れ> {
    if 往復.要約.gpu解除件数 == 0 {
        return Err(往復の実行で起きた束の解除.あるはずのものが無い破れ());
    }
    実行の数が期待どおりであることを課す("GPU解除件数", &静止.名前, 静止.要約.gpu解除件数, 0)?;
    let (往復の読込, 静止の読込) = (往復.要約.ディスク読込件数, 静止.要約.ディスク読込件数);
    解除した束を読み直したことの判定名(往復の読込, 静止の読込).真であることを課す(往復の読込 > 静止の読込)?;
    for 実行 in [往復, 静止] {
        実行の数が期待どおりであることを課す("最大台帳登録数", &実行.名前, 実行.要約.最大台帳登録数, 常駐チャンク数)?;
    }
    Ok(())
}

/// 解除と再読込を経た終状態が、一度も解除していない静止だけの実行と同じであること。
/// 可視材料が残れば登録数が、個体変換SSBOや可視ID列が残れば確保数が、群が二重に登録されれば候補数と発行数が食い違う。
/// 影の側は距離区分ごとに個体数と発行数を突き合わせる。1つの距離区分だけが食い違う残留を、距離区分をまたいだ合計では取り逃がすためである。
///
/// 台帳については最大でなく最終フレームの登録数を見る。最大は実行の途中のどこかで達した値であり終状態を表さないため、
/// 往復の終わりに不要な束が残っていても静止だけの実行と同じ値になりうる。両方の実行の最終値が常駐25と一致することを求める。
pub(in super::super) fn 残留がないことを検査する(往復: &実行, 静止: &実行) -> Result<(), 判定の破れ> {
    let 一覧: [(&str, u64, u64); 5] = [
        ("最終台帳登録数", 往復.要約.最終台帳登録数, 静止.要約.最終台帳登録数),
        ("可視材料登録数", 往復.計数.可視材料登録数, 静止.計数.可視材料登録数),
        ("GPU確保の現在数", 往復.計数.現在確保数, 静止.計数.現在確保数),
        ("シーンパス候補数", 往復.計数.シーン.候補数, 静止.計数.シーン.候補数),
        (
            "距離区分の和集合の可視数",
            往復.計数.可視個体の選別.距離区分の和集合の可視数,
            静止.計数.可視個体の選別.距離区分の和集合の可視数,
        ),
    ];
    for (名前, 往復値, 静止値) in 一覧 {
        実行どうしで同じ数であることを課す(名前, "往復", 往復値, "静止", 静止値)?;
    }
    for (番号, (往復の距離区分, 静止の距離区分)) in 往復.計数.距離区分別のシャドウ.iter().zip(&静止.計数.距離区分別のシャドウ).enumerate()
    {
        実行どうしで同じ数であることを課す(
            &format!("シャドウ距離区分{番号}個体数"),
            "往復",
            往復の距離区分.個体数,
            "静止",
            静止の距離区分.個体数,
        )?;
        実行どうしで同じ数であることを課す(
            &format!("シャドウ距離区分{番号}発行数"),
            "往復",
            往復の距離区分.発行数,
            "静止",
            静止の距離区分.発行数,
        )?;
    }
    for 実行 in [往復, 静止] {
        実行の数が期待どおりであることを課す("最終台帳登録数", &実行.名前, 実行.要約.最終台帳登録数, 常駐チャンク数)?;
    }
    実行の数が期待どおりであることを課す("可視材料登録数", &静止.名前, 静止.計数.可視材料登録数, 常駐チャンク数)
}

/// 実測を綴りへ入れるのは、真偽で課す判定が比べた数を文面へ出せないためである。
fn 解除した束を読み直したことの判定名(往復の読込: u64, 静止の読込: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "往復の読込{往復の読込}件が静止だけの{静止の読込}件を上回ること(上回らないなら解除した束を読み直していない)"
    ))
}
