//! 変動が資源を動かさないことについての判定。担当するのは、段と可視の変動がディスクI/OもGPU確保も起こさないことと、
//! どの実行も上限と検証件数を満たすことを見ることである。

use super::super::run::実行;
use super::{実行どうしで同じ数であることを課す, 実行の数が期待どおりであることを課す};
use crate::acceptance::{判定の名前, 判定の破れ};

const 地形詳細段が変わったフレーム: 判定の名前 =
    判定の名前::定数から生成する("往復の実行で地形詳細段が変わったフレーム(これが無いと段変更時の読込判定は空振りである)");

/// 移動のあいだに地形詳細段が実際に変わっていること。変わっていなければ段変更時の読込0件の判定が空振りになる。
pub(in super::super) fn 段が実際に変わることを検査する(往復: &実行) -> Result<(), 判定の破れ> {
    if 往復.要約.詳細段の変更フレーム数 == 0 {
        return Err(地形詳細段が変わったフレーム.あるはずのものが無い破れ());
    }
    Ok(())
}

/// 可視判定の変動がディスクI/Oも束の解除再読込もGPU再確保も起こさないこと。
/// カメラを往復させた実行とそうでない実行は経路が同じであるため必要集合の列も同じであり、違うのは可視数だけである。
/// 可視数が一致してしまう実行では対照にならないため、違うことを先に確かめる。
pub(in super::super) fn 可視の変動が資源を動かさないことを検査する(
    カメラ静止: &実行,
    カメラ往復: &実行,
) -> Result<(), 判定の破れ> {
    let (静止の可視数, 往復の可視数) = (カメラ静止.計数.シーン.可視数, カメラ往復.計数.シーン.可視数);
    可視数が動くことの判定名(静止の可視数).真であることを課す(静止の可視数 != 往復の可視数)?;
    let 一覧: [(&str, u64, u64); 5] = [
        ("ディスク読込件数", カメラ静止.要約.ディスク読込件数, カメラ往復.要約.ディスク読込件数),
        (
            "ディスク読込バイト数",
            カメラ静止.要約.ディスク読込バイト数,
            カメラ往復.要約.ディスク読込バイト数,
        ),
        ("GPU解除件数", カメラ静止.要約.gpu解除件数, カメラ往復.要約.gpu解除件数),
        ("GPU確保の現在数", カメラ静止.計数.現在確保数, カメラ往復.計数.現在確保数),
        ("GPU確保の最大同時数", カメラ静止.計数.最大同時確保数, カメラ往復.計数.最大同時確保数),
    ];
    for (名前, 静止値, 往復値) in 一覧 {
        実行どうしで同じ数であることを課す(名前, "カメラ静止", 静止値, "カメラ往復", 往復値)?;
    }
    Ok(())
}

/// 地形詳細段が変わったフレームで読込が始まっていないこと、容量が上限の内側であること、validationが0件であることを見る。
pub(in super::super) fn 実行ごとの上限を検査する(実行一覧: &[&実行], 上限バイト数: u64) -> Result<(), 判定の破れ> {
    for 実行 in 実行一覧 {
        実行の数が期待どおりであることを課す(
            "段変更フレームの読込開始件数",
            &実行.名前,
            実行.要約.詳細段の変更時の読込開始件数,
            0,
        )?;
        実行の数が期待どおりであることを課す("validation件数", &実行.名前, 実行.計数.validation件数, 0)?;
        使用量の判定名(&実行.名前, "最大RAM使用量").上限を課す(実行.要約.最大ramバイト数, 上限バイト数)?;
        使用量の判定名(&実行.名前, "最大VRAM使用量").上限を課す(実行.要約.最大vramバイト数, 上限バイト数)?;
    }
    Ok(())
}

/// 実測を綴りへ入れるのは、真偽で課す判定が比べた数を文面へ出せないためである。
fn 可視数が動くことの判定名(静止の可視数: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "カメラを往復させると可視数が{静止の可視数}から変わること(変わらないなら可視の変動が起きておらず対照にならない)"
    ))
}

fn 使用量の判定名(実行名: &str, 量の名前: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{実行名}の実行の{量の名前}"))
}
