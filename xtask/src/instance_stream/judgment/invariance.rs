//! 変動が資源を動かさないことについての判定。担当するのは、段と可視の変動がディスクI/OもGPU確保も起こさないことと、
//! どの実行も上限と検証件数を満たすことを見ることである。

use super::super::run::実行;
use super::{一致を求める, 期待値を求める};

/// 移動のあいだに地形詳細段が実際に変わっていること。変わっていなければ段変更時の読込0件の判定が空振りになる。
pub(in super::super) fn 段が実際に変わることを検査する(往復: &実行) -> Result<(), String> {
    if 往復.要約.lod変更フレーム数 == 0 {
        return Err("往復の実行で地形詳細段が一度も変わらなかった。段変更時の読込判定が空振りである".to_string());
    }
    Ok(())
}

/// 可視判定の変動がディスクI/Oも束の解除再読込もGPU再確保も起こさないこと。
/// カメラを往復させた実行とそうでない実行は経路が同じであるため必要集合の列も同じであり、違うのは可視数だけである。
/// 可視数が一致してしまう実行では対照にならないため、違うことを先に確かめる。
pub(in super::super) fn 可視の変動が資源を動かさないことを検査する(
    カメラ静止: &実行, カメラ往復: &実行
) -> Result<(), String> {
    if カメラ静止.計数.シーン.可視数 == カメラ往復.計数.シーン.可視数 {
        return Err(format!(
            "カメラを往復させても可視数が{}のままである。可視の変動が起きておらず対照にならない",
            カメラ静止.計数.シーン.可視数
        ));
    }
    let 一覧: [(&str, u64, u64); 5] = [
        ("ディスク読込件数", カメラ静止.要約.ディスク読込件数, カメラ往復.要約.ディスク読込件数),
        (
            "ディスク読込バイト数",
            カメラ静止.要約.ディスク読込バイト数,
            カメラ往復.要約.ディスク読込バイト数,
        ),
        ("GPU解除件数", カメラ静止.要約.gpu解除件数, カメラ往復.要約.gpu解除件数),
        ("GPU確保の現在数", カメラ静止.計数.現在確保数, カメラ往復.計数.現在確保数),
        ("GPU確保の最大同時数", カメラ静止.計数.最大同時確保数, カメラ往復.計数.最大同時確保数),
    ];
    for (名前, 静止値, 往復値) in 一覧 {
        一致を求める(名前, "カメラ静止", 静止値, "カメラ往復", 往復値)?;
    }
    Ok(())
}

/// 地形詳細段が変わったフレームで読込が始まっていないこと、容量が上限の内側であること、validationが0件であること。
pub(in super::super) fn 実行ごとの上限を検査する(実行一覧: &[&実行], 上限バイト数: u64) -> Result<(), String> {
    for 実行 in 実行一覧 {
        期待値を求める("段変更フレームの読込開始件数", &実行.名前, 実行.要約.lod変更時読込開始件数, 0)?;
        期待値を求める("validation件数", &実行.名前, 実行.計数.validation件数, 0)?;
        if 実行.要約.最大ramバイト数 > 上限バイト数 || 実行.要約.最大vramバイト数 > 上限バイト数 {
            return Err(format!(
                "{}の実行の使用量が上限{上限バイト数}を超えた: RAM {}、VRAM {}",
                実行.名前, 実行.要約.最大ramバイト数, 実行.要約.最大vramバイト数
            ));
        }
    }
    Ok(())
}
