//! 目視見本1条件ぶんの起動の指定。受け取るのは時刻、返すのは実行環境へ渡す起動指定である。
//! 起こす手順そのものは検収の共通語彙の実行環境が持ち、ここは時刻ごとに違う選択肢だけを決める。
//!
//! シーン名を`terrain_visual`にすることが、庭を正面から見る初期カメラと、書き換えもピクセル判定も持たない検収計画と、
//! 天空の遠方環境の間接照明方針を同時に選ばせる。時刻の絵は空も本番の経路のまま描くため、起動指定で空を足す必要はない。
//! 領域マスクを撮る起動指定は`crate::sample_world_region`が持つ。領域の識別と同じ条件で撮ることを1箇所で担保するためである。
//! 監視対象シェーダーは指定しない。指定しないと埋め込みシェーダーで走り、リポジトリの`shaders/`へ監視の入口が向かない。
//! 時間再構成は世界の宣言どおりに効かせる。この入口が出すのはオーナーが本番の絵として見る材料であり、本番と違う軸で描いた絵は見本にならない。
//! 破綻防止帯の判定は地面の画素の割合を見ており、バイト一致に依らないため、フレームをまたぐ混合が入っても成立する。

use std::path::PathBuf;

use crate::acceptance::{アプリの起こし方, アプリの起動指定, 描画フレーム数, 描画検収の実行環境, 検収エラー};
use crate::visual_sample_world::{目視見本世界のアセットルートを作る, 目視見本世界のシーン名};

/// 描くフレーム数。空と間接照明の焼き上げが定常へ入り、絵が時刻だけで決まる状態まで進める本数である。
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(120);

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        目視見本世界のアセットルートを作る(),
        出力ディレクトリ,
    )
}

pub(super) fn 時刻の起動指定を組み立てる(一日内秒: &str) -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(目視見本世界のシーン名, フレーム数).値を持つ選択肢を足す("--time-of-day", 一日内秒)
}
