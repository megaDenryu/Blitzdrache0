//! 目視見本の絵の破綻防止帯の判定。受け取るのは1時刻ぶんの読み戻し画像と地面を照らす光の別、
//! 返すのは飽和と黒潰れの画素の割合である。
//!
//! 判定領域を画面下側の矩形に固定するのは、初期カメラが固定されており、地面と台座と球の列が必ずこの範囲へ写るためである。
//! 領域マスクを別に撮る方式(`sky-time`)を採らないのは、この入口が持つ機械条件が破綻の有無だけであり、
//! 空とジオメトリの境を1画素の精度で分ける必要が無いからである。1回の起動を節約する側を選んでいる。
//!
//! 閾値と割合の上限は`xtask/src/damage_band.rs`が持つ台帳から引く。ただし黒潰れの割合の上限は、
//! 太陽が地平線より上にある時刻にだけ課す。この世界の地面は実測に近い暗いアルベドを持つため、
//! 自動露出の無い夜は地面が正しく黒へ沈み(2026-08-04の実測で判定領域の0.88)、上限を課すと破綻でない絵を落とす。
//! 夜に課すのは「判定領域の全画素が黒潰れではない」ことであり、間接光が届いていることの下限として置く。
//!
//! 注意: RGBA8の読み戻しからは非有限値をそのまま観測できない。明るさの圧縮とsRGB符号化を通った後の値が帯に
//! 収まることを、有限性の観測できる代理として置く。

use crate::damage_band::{割合にする, 飽和の下限, 飽和割合の上限, 黒潰れの上限, 黒潰れ割合の上限};
use crate::pixel_region::画面領域;
use crate::vegetation_run::実行結果;

/// 判定領域の、画面の幅と高さに対する割合。俯角14度の構図では地平線が画面の高さの半ばに来るため、その下側を取る。
const 領域の左: f64 = 0.10;
const 領域の右: f64 = 0.90;
const 領域の上: f64 = 0.55;
const 領域の下: f64 = 0.98;

/// その時刻に地面を照らす光。夜だけが間接光だけになる。
pub(super) enum 地面を照らす光 {
    方向光と間接光,
    間接光だけ,
}

pub(super) fn 破綻防止帯を判定する(名前: &str, 画像: &実行結果, 光: &地面を照らす光) -> Result<String, String> {
    let 領域 = 判定領域を作る(画像);
    let 画素数 = 領域.画素数();
    if 画素数 == 0 {
        return Err("破綻防止帯の判定領域が空になった".to_string());
    }
    let 飽和割合 = 割合にする(全成分が範囲内の画素を数える(画像, &領域, 飽和の下限, u8::MAX), 画素数);
    let 黒潰れ割合 = 割合にする(全成分が範囲内の画素を数える(画像, &領域, 0, 黒潰れの上限), 画素数);
    if 飽和割合 > 飽和割合の上限 {
        return Err(format!("{名前}の地面の飽和画素が{飽和割合:.4}で上限{飽和割合の上限}を超えた"));
    }
    黒潰れを判定する(名前, 黒潰れ割合, 光)?;
    Ok(format!("{名前}は黒潰れ{黒潰れ割合:.4}・飽和{飽和割合:.4}"))
}

fn 黒潰れを判定する(名前: &str, 黒潰れ割合: f64, 光: &地面を照らす光) -> Result<(), String> {
    match 光 {
        地面を照らす光::方向光と間接光 if 黒潰れ割合 > 黒潰れ割合の上限 => {
            Err(format!("{名前}の地面の黒潰れ画素が{黒潰れ割合:.4}で上限{黒潰れ割合の上限}を超えた"))
        }
        地面を照らす光::間接光だけ if 黒潰れ割合 >= 1.0 => {
            Err(format!("{名前}の地面が判定領域の全画素で黒潰れした(間接光が1画素も届いていない)"))
        }
        地面を照らす光::方向光と間接光 | 地面を照らす光::間接光だけ => Ok(()),
    }
}

fn 判定領域を作る(画像: &実行結果) -> 画面領域 {
    画面領域 {
        x開始: 割合を画素へ(領域の左, 画像.幅),
        x終端: 割合を画素へ(領域の右, 画像.幅),
        y開始: 割合を画素へ(領域の上, 画像.高さ),
        y終端: 割合を画素へ(領域の下, 画像.高さ),
    }
}

fn 割合を画素へ(割合: f64, 画素数: usize) -> usize {
    let 実数 = 割合 * 画素数を実数へ(画素数);
    let mut 位置 = 0usize;
    while 位置 < 画素数 && 画素数を実数へ(位置 + 1) <= 実数 {
        位置 += 1;
    }
    位置
}

fn 画素数を実数へ(値: usize) -> f64 {
    f64::from(u32::try_from(値).unwrap_or(u32::MAX))
}

/// 3成分すべてが範囲に入る画素を数える。明度1成分だけを見る`pixel_region`と別に持つのは、
/// 飽和も黒潰れも3成分そろっていることを条件にするためである。
fn 全成分が範囲内の画素を数える(画像: &実行結果, 領域: &画面領域, 下限: u8, 上限: u8) -> u64 {
    let mut 件数 = 0u64;
    for y in 領域.y開始..領域.y終端 {
        for x in 領域.x開始..領域.x終端 {
            let 先頭 = (y * 画像.幅 + x) * 4;
            if (0..3).all(|軸| 画像.rgba8[先頭 + 軸] >= 下限 && 画像.rgba8[先頭 + 軸] <= 上限) {
                件数 += 1;
            }
        }
    }
    件数
}
