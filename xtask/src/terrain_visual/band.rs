//! 目視見本の地面の破綻防止帯の判定。受け取るのは1時刻ぶんの読み戻し画像と地面の領域マスクと地面を照らす光の別、
//! 返すのは地面の画素に対する飽和と黒潰れの割合である。
//!
//! 判定の対象を領域マスクが地面と判定した画素だけに絞るのは、球も台座も小物も地面と違う明るさに写るためである。
//! 矩形で切ると、地面の割合を語っているつもりで小物の画素を数えることになり、その割合が何の性質を表すのか決まらない。
//!
//! 閾値と割合の上限は`xtask/src/damage_band.rs`が持つ台帳から引く。ただし黒潰れの割合の上限は、太陽が地平線より上にある
//! 時刻にだけ課す。この世界の地面は実測に近い暗いアルベドを持つため、自動露出の無い夜は地面が正しく8ビットの下限へ沈む。
//! 夜に上限を課すと破綻でない絵を落とすため、夜は測った割合を報告するだけにして判定へ使わない。
//!
//! 注意: RGBA8の読み戻しからは非有限値をそのまま観測できない。明るさの圧縮とsRGB符号化を通った後の値が帯に
//! 収まることを、有限性の観測できる代理として置く。

use crate::acceptance::読み戻し画像;
use crate::damage_band::{割合にする, 飽和の下限, 飽和割合の上限, 黒潰れの上限, 黒潰れ割合の上限};
use crate::sample_world_region::地面マスク;

/// その時刻に地面を照らす光。夜だけが間接光だけになる。
pub(super) enum 地面を照らす光 {
    方向光と間接光,
    間接光だけ,
}

pub(super) fn 破綻防止帯を判定する(
    名前: &str, 画像: &読み戻し画像, マスク: &地面マスク, 光: &地面を照らす光
) -> Result<String, String> {
    マスク.寸法が合うか(画像)?;
    let (黒潰れ, 飽和) = 地面の画素を数える(画像, マスク);
    let 黒潰れ割合 = 割合にする(黒潰れ, マスク.地面画素数);
    let 飽和割合 = 割合にする(飽和, マスク.地面画素数);
    if 飽和割合 > 飽和割合の上限 {
        return Err(format!("{名前}の地面の飽和画素が{飽和割合:.4}で上限{飽和割合の上限}を超えた"));
    }
    match 光 {
        地面を照らす光::方向光と間接光 if 黒潰れ割合 > 黒潰れ割合の上限 => {
            Err(format!("{名前}の地面の黒潰れ画素が{黒潰れ割合:.4}で上限{黒潰れ割合の上限}を超えた"))
        }
        地面を照らす光::方向光と間接光 => Ok(format!("{名前}は黒潰れ{黒潰れ割合:.4}・飽和{飽和割合:.4}")),
        地面を照らす光::間接光だけ => Ok(format!("{名前}は黒潰れ{黒潰れ割合:.4}(上限を課さない)・飽和{飽和割合:.4}")),
    }
}

/// 地面の画素のうち、3成分すべてが黒潰れの上限以下のものと、3成分すべてが飽和の下限以上のものを数える。
/// 3成分そろっていることを条件にするのは、1成分だけが端に張り付いた画素を破綻と呼ばないためである。
fn 地面の画素を数える(画像: &読み戻し画像, マスク: &地面マスク) -> (u64, u64) {
    let (mut 黒潰れ, mut 飽和) = (0_u64, 0_u64);
    for 添字 in 0..画像.画素数() {
        if !マスク.地面か(添字) {
            continue;
        }
        let 色 = 画像.添字の画素(添字);
        黒潰れ += u64::from(色.iter().all(|成分| *成分 <= 黒潰れの上限));
        飽和 += u64::from(色.iter().all(|成分| *成分 >= 飽和の下限));
    }
    (黒潰れ, 飽和)
}
