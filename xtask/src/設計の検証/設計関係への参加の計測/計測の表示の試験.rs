//! 設計関係への参加の計測の表示が、参加の答えを弱めるかどうかを、設計関係の答えを弱める欠落の有無で言い分けることを固定する試験。
//!
//! 保持する関係と分類は参加に数えない(`_doc/設計/設計オントロジー.md` 6.6節)。したがってそれだけを弱める欠落は、検証器の参加の答えを弱めない。
//! 欠落が1件でも在れば弱まると表示すると、読み手は反例が出るはずの母集団を反例の出ない母集団と読み誤る。

use blitz_design_verification::{プリミティブな関係の種類, 欠落が弱める答え, 落とした理由ごとの件数, 関係を落とした抽出の欠落, 関数の引数と戻り値の役目};

use crate::設計関係のモデル::抽出した設計関係グラフと抽出の欠け;

use super::参加の計測の試験のグラフ::試験のグラフ;
use super::設計関係への参加の計測;

// 渡した答えだけを弱める件を1件持つ欠落から計測を組み、表示の文を返す。
fn 答えを弱める欠落での表示(弱める答え一覧: Vec<欠落が弱める答え>) -> String {
    let 欠落 = 関係を落とした抽出の欠落::生成する(
        vec![落とした理由ごとの件数 {
            理由の説明: "試験が置いた読めない表記".to_string(),
            件数: 1,
            弱める答え一覧,
        }],
        &[],
    );
    let 抽出したもの = 抽出した設計関係グラフと抽出の欠け {
        グラフ: 試験のグラフ(),
        ..抽出した設計関係グラフと抽出の欠け::default()
    };
    設計関係への参加の計測::計測する(&抽出したもの, &欠落).to_string()
}

#[test]
fn 保持する関係と分類だけを弱める欠落では参加の答えが弱まると表示しない() {
    let 表示 = 答えを弱める欠落での表示(vec![欠落が弱める答え::プリミティブな関係(プリミティブな関係の種類::保持する), 欠落が弱める答え::分類]);
    assert!(!表示.contains("反例として答えず、未決定を答える"), "{表示}");
    assert!(表示.contains("設計関係の答えを弱める欠落が0件である"), "{表示}");
}

#[test]
fn 設計関係の答えを弱める欠落では参加の答えが弱まると件の説明とともに表示する() {
    let 表示 = 答えを弱める欠落での表示(vec![欠落が弱める答え::設計関係(関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す())]);
    assert!(表示.contains("反例として答えず、未決定を答える"), "{表示}");
    assert!(表示.contains("試験が置いた読めない表記: 1件"), "{表示}");
}
