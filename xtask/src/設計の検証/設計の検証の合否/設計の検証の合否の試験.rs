//! 反証済みの件数と、検証した命題の件数から合否を決める判断を固定する試験。
//!
//! `ExitCode` は `PartialEq` を持たないため、終了コードそのものを比べない。合否の判断を
//! `設計の検証の合否` の選択肢へ切り出し、その選択肢を比べる。終了コードへ写すメソッドはその型の1箇所だけである。
//! **反証済み・未決定・関係を落とした抽出の欠落のどれかが在れば不合格である**(2026-09-27。Issue #175 の第1段階の検収で親が採った指摘)。
//! 未決定と欠落を合格へ写す退行は、ゲートが黙って無効になる経路であるため、試験で固定する。
//! **命題を1件も検証しなかった実行は合格にしない。** これは受理の規則ではなく、検査器が1件も検査していない実行を
//! 合格として答えないという別の規約である。命題の集合が空になった事故が検証に通った状態と見分けられなくなる。
//! 欠落を取り込む工程(`命題が問う答えを弱める欠落を取り込む`)が、命題の集合が問う答えを弱める欠落だけを数えることも、入口と同じ組み合わせで固定する。

use super::{検証結果の件数, 設計の検証の合否};
use blitz_design_verification::{
    原子命題, 名前付きの命題, 命題, 命題の集合, 欠落が弱める答え, 落とした理由ごとの件数, 設計概念の識別用情報, 設計関係の結び付き方, 関係を落とした抽出の欠落, 関数の引数と戻り値の役目, 項
};
use blitz_design_verification::{命題名, 設計関係の有無命題};

#[test]
fn 反証済みが1件でもあれば不合格を答える() {
    let 件数 = 検証結果の件数 {
        証明済み: 3,
        反証済み: 1,
        未決定: 0,
        命題が問う答えを弱める欠落: 0,
    };
    assert_eq!(件数.合否を答える(), 設計の検証の合否::反証済みが在る);
}

#[test]
fn 反証済みが1件でもあれば未決定が在っても不合格を答える() {
    let 件数 = 検証結果の件数 {
        証明済み: 0,
        反証済み: 1,
        未決定: 2,
        命題が問う答えを弱める欠落: 0,
    };
    assert_eq!(件数.合否を答える(), 設計の検証の合否::反証済みが在る);
}

#[test]
fn 件数が3つとも0件のときは検証した命題が1件も無いを答える() {
    assert_eq!(検証結果の件数::default().合否を答える(), 設計の検証の合否::検証した命題が1件も無い);
}

#[test]
fn 証明済みが1件でもあれば合格を答える() {
    let 件数 = 検証結果の件数 {
        証明済み: 1,
        反証済み: 0,
        未決定: 0,
        命題が問う答えを弱める欠落: 0,
    };
    assert_eq!(件数.合否を答える(), 設計の検証の合否::全件が証明済みで問う答えを弱める欠落も無い);
}

/// 反証: 未決定を合格へ写すと、検証器が答えを弱めた公理が何も確かめないまま検証が通る。
#[test]
fn 未決定が1件でもあれば不合格を答える() {
    let 件数 = 検証結果の件数 {
        証明済み: 4,
        反証済み: 0,
        未決定: 1,
        命題が問う答えを弱める欠落: 0,
    };
    assert_eq!(件数.合否を答える(), 設計の検証の合否::未決定が在る);
}

/// 反証: 欠落を合格へ写すと、抽出が命題の問う答えの宣言を落とした状態で、エッジの不在を根拠にした答えのまま検証が通る。
#[test]
fn 命題が問う答えを弱める欠落が1件でもあれば全件が証明済みでも不合格を答える() {
    let 件数 = 検証結果の件数 {
        証明済み: 5,
        反証済み: 0,
        未決定: 0,
        命題が問う答えを弱める欠落: 1,
    };
    assert_eq!(件数.合否を答える(), 設計の検証の合否::命題が問う答えを弱める欠落が在る);
}

// 渡した答えだけを弱める欠落1件と、変換用の素材にするの設計関係を問う命題1件を組み、欠落を取り込んで1件を証明済みにした件数を返す。
fn 欠落を取り込んだ件数(弱める答え: 欠落が弱める答え) -> 検証結果の件数 {
    let 欠落 = 関係を落とした抽出の欠落::生成する(
        vec![落とした理由ごとの件数 {
            理由の説明: "試験が置いた読めない表記".to_string(),
            件数: 1,
            弱める答え一覧: vec![弱める答え],
        }],
        &[],
    );
    let 原子 = 原子命題::設計関係の有無命題(設計関係の有無命題::生成する(
        項::名指した概念(設計概念の識別用情報::処理として生成する("blitz_esca::旅行者", "動かす")),
        関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す(),
        項::名指した概念(設計概念の識別用情報::型として生成する("blitz_esca::旅行者", "旅行者の意図")),
    ));
    let 命題の集合 = 命題の集合::生成する(命題名::生成する("試験"), vec![名前付きの命題::生成する(命題名::生成する("処理が意図を変換用の素材にする"), 命題::原子から組む(原子))]);
    let mut 件数 = 検証結果の件数 {
        証明済み: 1, ..検証結果の件数::default()
    };
    件数.命題が問う答えを弱める欠落を取り込む(&欠落, &命題の集合);
    件数
}

/// 反証: 欠落の全件で不合格にすると、命題が問わない答え(識別する)だけを弱める欠落が、どの命題の答えも弱めないのに検証を落とす。
#[test]
fn 命題が問わない答えだけを弱める欠落は不合格にしない() {
    let 件数 = 欠落を取り込んだ件数(欠落が弱める答え::設計関係(設計関係の結び付き方::識別する));
    assert_eq!(件数.合否を答える(), 設計の検証の合否::全件が証明済みで問う答えを弱める欠落も無い);
}

/// 反証: 取り込みが命題の問う答えを見ないと、命題の答えを弱める欠落を見逃して合格を答える。
#[test]
fn 命題が問う答えを弱める欠落は不合格にする() {
    let 件数 = 欠落を取り込んだ件数(欠落が弱める答え::設計関係(関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す()));
    assert_eq!(件数.合否を答える(), 設計の検証の合否::命題が問う答えを弱める欠落が在る);
}
