//! 関数の署名の計測の試験。関数の役割の宣言に包まれていない関数だけが手がかりの一覧に載ることと、手がかりが型の分類とプリミティブな関係から
//! 決まることと、関数の署名を読めなかった箇所を理由ごとに数えることを固定する。

use super::{遷移の形の手がかり, 関数の署名の計測};
use crate::設計関係のモデル::原文から設計関係グラフと抽出の欠けを組む;
use blitz_design_verification::受け手の種類;

const 原文: &str = "pub enum 進行の操作 {\n    決定する,\n}\n\nimpl Mコマンド for 進行の操作 {}\n\npub struct ゲームの進行段階 {\n    段階の番号: u8,\n}\n\nimpl M状態 for ゲームの進行段階 {}\n\nimpl ゲームの進行段階 {\n    pub fn 次の段階を決める(self, 操作: &進行の操作) -> ゲームの進行段階 {\n        fn 内側() {}\n        todo!()\n    }\n\n    pub fn 包まれた遷移(self, 操作: &進行の操作) -> ゲームの進行段階 {\n        todo!()\n    }\n}\n\nconst _: M遷移が受け取る命令で決まる遷移関数<ゲームの進行段階, 進行の操作> = M遷移が受け取る命令で決まる遷移関数::生成する(ゲームの進行段階::包まれた遷移);\n";

fn 計測する() -> 関数の署名の計測 {
    関数の署名の計測::計測する(&原文から設計関係グラフと抽出の欠けを組む(&[("crates/blitz_game/src/進行段階.rs", 原文)]))
}

// その手がかりの一覧に載った関数のパスを並べる。
fn 載ったパス一覧(計測: &関数の署名の計測, 手がかり: 遷移の形の手がかり) -> Vec<String> {
    計測.手がかりごとの一覧.iter().filter(|(当たった, _)| *当たった == 手がかり).flat_map(|(_, 一覧)| 一覧.iter().map(|関数| 関数.パス.clone())).collect()
}

#[test]
fn 宣言の無い関数だけが命令の手がかりの一覧に載る() {
    let 計測 = 計測する();
    let 期待 = vec!["blitz_game::進行段階::ゲームの進行段階::次の段階を決める".to_string()];
    assert_eq!(載ったパス一覧(&計測, 遷移の形の手がかり::命令を引数に取る), 期待);
    assert!(載ったパス一覧(&計測, 遷移の形の手がかり::出来事を返す).is_empty());
    let 載った関数 = 計測.手がかりごとの一覧.iter().flat_map(|(_, 一覧)| 一覧).find(|関数| 関数.パス == 期待[0]);
    assert!(載った関数.is_some_and(|関数| 関数.受け手 == 受け手の種類::値), "{:?}", 計測.手がかりごとの一覧);
}

#[test]
fn 関数の本体の中の関数を読めなかった箇所として理由ごとに数える() {
    let 計測 = 計測する();
    let 件 = 計測.読めなかった理由ごとの件数.iter().find(|件| 件.呼び名 == "項目の位置でない関数である");
    assert!(件.is_some_and(|件| 件.件数 == 1), "{:?}", 計測.読めなかった理由ごとの件数);
}
