//! 遷移の形の手がかりとは、関数の署名が遷移の役割の形をしていることを示す、署名と型の分類の組み合わせのことである。受け取るのは抽出したもの、
//! 返すのは関数の役割の宣言に包まれていない関数ごとの、当たった手がかりの並びである。
//!
//! 手がかりは5つある。命令(`Mコマンド`・`M命令の組`)を引数に取る。状態(`M状態`)を受けて同じ状態を返す。規則(`M規則`)を引数に取る。
//! 解釈前の入力(`M解釈前の入力`)を引数に取る。出来事(`Mイベント`)を返す。状態を受けるとは、所有者が状態で受け手を持つか、状態を引数に取ることである。
//! 状態を返すかは `Result` と組の中の型を含めて見る。署名の読み方が `Result<T, E>` を T と E の返すへ分けて導くためである。

use crate::設計関係のモデル::{抽出した設計関係グラフと抽出の欠け, 設計概念への参照, 設計関係グラフ};
use blitz_design_verification::{プリミティブな関係の種類, 受け手の種類, 関数の署名の事実};

use super::宣言の無い関数;

/// 遷移の形の手がかり。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 遷移の形の手がかり {
    命令を引数に取る,
    状態を受けて同じ状態を返す,
    規則を引数に取る,
    解釈前の入力を引数に取る,
    出来事を返す,
}

impl 遷移の形の手がかり {
    /// 5つの手がかりを表示の順に並べた全件。
    pub const fn 全部() -> [Self; 5] {
        [Self::命令を引数に取る, Self::状態を受けて同じ状態を返す, Self::規則を引数に取る, Self::解釈前の入力を引数に取る, Self::出来事を返す]
    }

    /// 人が読む見出し。
    pub const fn 見出し(self) -> &'static str {
        match self {
            Self::命令を引数に取る => "Mコマンドか M命令の組 を引数に取る",
            Self::状態を受けて同じ状態を返す => "M状態を受け手か引数で受けて、同じ M状態を返す",
            Self::規則を引数に取る => "M規則を引数に取る",
            Self::解釈前の入力を引数に取る => "M解釈前の入力を引数に取る",
            Self::出来事を返す => "Mイベントを返す",
        }
    }
}

/// 関数の役割の宣言に包まれていない関数ごとに、当たった手がかりの並び。手がかりに1つも当たらない関数も、空の並びで含める。
pub(super) fn 宣言の無い関数の手がかり一覧(抽出したもの: &抽出した設計関係グラフと抽出の欠け) -> Vec<(宣言の無い関数, Vec<遷移の形の手がかり>)> {
    let 事実 = &抽出したもの.事実;
    let 包まれた処理一覧: Vec<設計概念への参照> = 事実.関数の役割の宣言一覧.iter().map(|宣言| 宣言.処理.参照を組む()).collect();
    事実
        .関数の署名一覧
        .iter()
        .filter(|署名| !包まれた処理一覧.contains(&署名.処理.参照を組む()))
        .map(|署名| {
            let 関数 = 宣言の無い関数 {
                パス: 署名.処理.識別子().表記(),
                受け手: 署名.受け手,
            };
            (関数, 署名の手がかり(&抽出したもの.グラフ, 署名))
        })
        .collect()
}

// 署名1件が当たる手がかりの並び。
fn 署名の手がかり(グラフ: &設計関係グラフ, 署名: &関数の署名の事実) -> Vec<遷移の形の手がかり> {
    let 処理 = 署名.処理.参照を組む();
    let 相手一覧 = |種類| -> Vec<&設計概念への参照> { グラフ.プリミティブな関係を貸す().全件().iter().filter(|関係| 関係.種類 == 種類 && 関係.主語 == 処理).map(|関係| &関係.目的語).collect() };
    let (引数一覧, 戻り値一覧) = (相手一覧(プリミティブな関係の種類::引数に取る), 相手一覧(プリミティブな関係の種類::返す));
    let 持つ = |型: &設計概念への参照, マーカー名: &str| グラフ.分類を貸す().概念の分類(型).iter().any(|トレイト| トレイト.識別子().名前 == マーカー名);
    let 引数に持つ = |マーカー名一覧: &[&str]| 引数一覧.iter().any(|型| マーカー名一覧.iter().any(|名前| 持つ(型, 名前)));
    let 受けた状態一覧: Vec<&設計概念への参照> = 所有者一覧(グラフ, &処理)
        .into_iter()
        .filter(|_| 署名.受け手 != 受け手の種類::無し)
        .chain(引数一覧.iter().copied())
        .filter(|型| 持つ(型, "M状態"))
        .collect();
    let 候補 = [
        (遷移の形の手がかり::命令を引数に取る, 引数に持つ(&["Mコマンド", "M命令の組"])),
        (遷移の形の手がかり::状態を受けて同じ状態を返す, 受けた状態一覧.iter().any(|状態| 戻り値一覧.contains(状態))),
        (遷移の形の手がかり::規則を引数に取る, 引数に持つ(&["M規則"])),
        (遷移の形の手がかり::解釈前の入力を引数に取る, 引数に持つ(&["M解釈前の入力"])),
        (遷移の形の手がかり::出来事を返す, 戻り値一覧.iter().any(|型| 持つ(型, "Mイベント"))),
    ];
    候補.into_iter().filter(|(_, 当たるか)| *当たるか).map(|(手がかり, _)| 手がかり).collect()
}

// その処理を関連関数として持つ所有者(型かトレイト)の並び。
fn 所有者一覧<'a>(グラフ: &'a 設計関係グラフ, 処理: &設計概念への参照) -> Vec<&'a 設計概念への参照> {
    グラフ
        .プリミティブな関係を貸す()
        .全件()
        .iter()
        .filter(|関係| 関係.種類 == プリミティブな関係の種類::関連関数として持つ && &関係.目的語 == 処理)
        .map(|関係| &関係.主語)
        .collect()
}
