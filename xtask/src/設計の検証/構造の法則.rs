/// 構造の法則の命題の集合を組む。存在理由の公理の6つの後ろに、状態を受けて返す処理の宣言の法則を並べる。
pub fn 構造の法則の命題の集合を組む() -> 命題の集合 {
    let mut 命題一覧 = 存在理由の公理::存在理由の公理の一覧を組む();
    命題一覧.push(名前付きの命題::生成する(状態を受けて返す処理の宣言の法則::法則の名前, 状態を受けて返す処理の宣言の法則::法則を組む()));
    命題の集合::生成する("設計解釈マーカーごとの存在理由の公理と、状態を受けて返す処理の宣言の法則", 命題一覧)
}
