//! 設計の検証の合否とは、`cargo xtask design-verify` が検証した命題の件数と関係を落とした抽出の欠落の件数から答える、合格か不合格の理由かの判断のことである。
//! 受け取るのは結果ごとの件数、返すのは合否と、それを写した終了コードである。入口(`設計の検証.rs`)は抽出と検証の段取りと内訳の表示を持ち、
//! 件数から合否を決めて終了コードへ写す判断はここが持つ。
//! **反証済み・未決定・命題の集合が問う答えを弱める抽出の欠落のどれかが1件でもあれば不合格である**(2026-09-27。Issue #175 の第1段階の検収で親が採った指摘。
//! 欠落を問う答えを弱めるものに絞ったのは Issue #175 の第2段階の親の判断)。欠落で不合格にする目的は、欠落が命題の答えを黙って弱めることを止めることであり、
//! どの命題も問わない答えだけを弱める欠落は、どの命題の答えも弱めないためである。その件数は入口が表示する。
//! いまの命題の集合は存在理由の公理の6つだけであり、付いているマーカー・設計関係の3語(変換用の素材にする・参照する・生成する)・保持するの答えだけを問う。
//! 識別する・書き換えるの答えだけを弱める欠落は合否に効かない。

use std::process::ExitCode;

use blitz_design_verification::{命題の集合, 検証の集計, 関係を落とした抽出の欠落};

#[cfg(test)]
#[path = "設計の検証の合否/設計の検証の合否の試験.rs"]
mod 設計の検証の合否の試験;

/// 結果ごとの件数と、命題の集合が問う答えを弱める抽出の欠落の件数。検証した命題を数え、終了コードを答える。
#[derive(Debug, Clone, Copy, Default)]
pub struct 検証結果の件数 {
    証明済み: usize,
    反証済み: usize,
    未決定: usize,
    命題が問う答えを弱める欠落: usize,
}

/// 検証の入口が答える合否。検証した命題が全部証明済みで、命題の集合が問う答えを弱める抽出の欠落も無いときだけ合格である。
/// 判断を選択肢として持つのは、`ExitCode` が `PartialEq` を持たず、終了コードのままでは判断を試験で固定できないためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum 設計の検証の合否 {
    /// 検証した命題が全部証明済みであり、関係を落とした抽出の欠落も無い。
    全件が証明済みで問う答えを弱める欠落も無い,
    /// 反証された命題が1件以上在る。
    反証済みが在る,
    /// 抽出が関係を組めなかった箇所のうち、命題の集合が問う答えを弱めるものが1件以上在る。その答えについてエッジの不在を根拠にした結果を信用できない。
    命題が問う答えを弱める欠落が在る,
    /// 証明も反証もできなかった命題が1件以上在る。
    未決定が在る,
    /// 検証した命題が1件も無い。命題の集合が空であり、何も検証していない。
    検証した命題が1件も無い,
}

impl 検証結果の件数 {
    /// 抽出の欠落のうち、命題の集合が問う答え(`命題の集合::問う答え一覧`)を弱める件の件数を数えて取り込み、その件数を答える。
    /// 合否に効く欠落の数え方はここだけが持ち、入口はこの件数を表示に使う。
    pub fn 命題が問う答えを弱める欠落を取り込む(&mut self, 欠落: &関係を落とした抽出の欠落, 命題の集合: &命題の集合) -> usize {
        self.命題が問う答えを弱める欠落 = 欠落.答えを弱める件の件数(&命題の集合.問う答え一覧());
        self.命題が問う答えを弱める欠落
    }

    /// 構造の法則の集計をこの件数へ足す。命題の集合が数えた結果を、入口の集計と別に持たない。
    pub fn 構造の集計を取り込む(&mut self, 集計: &検証の集計) {
        self.証明済み += 集計.証明済みの件数;
        self.反証済み += 集計.反証済みの件数;
        self.未決定 += 集計.未決定の件数;
    }

    /// 件数から合否を答える。反証済み・欠落・未決定の順に不合格の理由を選ぶ。
    /// **3つとも0件のときは合格を答えない。** 命題を1件も検証していない実行が合格を名乗ると、命題の集合が空になった事故が
    /// 検証に通った状態と見分けられなくなる(グローバルCLAUDE.md「検査器は解析できなかった入力を黙って対象から外してはならない」)。
    fn 合否を答える(&self) -> 設計の検証の合否 {
        if self.反証済み > 0 {
            return 設計の検証の合否::反証済みが在る;
        }
        if self.命題が問う答えを弱める欠落 > 0 {
            return 設計の検証の合否::命題が問う答えを弱める欠落が在る;
        }
        if self.未決定 > 0 {
            return 設計の検証の合否::未決定が在る;
        }
        if self.検証した命題の件数() == 0 {
            return 設計の検証の合否::検証した命題が1件も無い;
        }
        設計の検証の合否::全件が証明済みで問う答えを弱める欠落も無い
    }

    /// 結果ごとの件数の合計。合否の判断が、1件も検証していない実行をこの合計で見分ける。
    fn 検証した命題の件数(&self) -> usize {
        self.証明済み + self.反証済み + self.未決定
    }

    /// 結果ごとの件数を表示し、合否を写した終了コードを答える。
    pub fn 結果を表示して終了コードを答える(&self) -> ExitCode {
        println!("[xtask] design-verify: 証明済み{}件・反証済み{}件・未決定{}件", self.証明済み, self.反証済み, self.未決定);
        let 合否 = self.合否を答える();
        match 合否 {
            設計の検証の合否::全件が証明済みで問う答えを弱める欠落も無い | 設計の検証の合否::反証済みが在る => {}
            設計の検証の合否::命題が問う答えを弱める欠落が在る => {
                eprintln!(
                    "[xtask] design-verify: 命題の集合が問う答えを弱める抽出の欠落が{}件在る。エッジの不在を根拠にした答えを信用できないため合格として答えない",
                    self.命題が問う答えを弱める欠落
                );
            }
            設計の検証の合否::未決定が在る => eprintln!("[xtask] design-verify: 未決定の命題が{}件在る。確かめられなかった命題を合格として答えない", self.未決定),
            設計の検証の合否::検証した命題が1件も無い => {
                eprintln!("[xtask] design-verify: 検証した命題が1件も無い(命題の集合が空である)。検証していないことを合格として答えない");
            }
        }
        合否.終了コードへ写す()
    }
}

impl 設計の検証の合否 {
    /// 合否をプロセスの終了コードへ写す。写すのはこの1箇所だけである。
    fn 終了コードへ写す(self) -> ExitCode {
        match self {
            Self::全件が証明済みで問う答えを弱める欠落も無い => ExitCode::SUCCESS,
            Self::反証済みが在る | Self::命題が問う答えを弱める欠落が在る | Self::未決定が在る | Self::検証した命題が1件も無い => ExitCode::FAILURE,
        }
    }
}
