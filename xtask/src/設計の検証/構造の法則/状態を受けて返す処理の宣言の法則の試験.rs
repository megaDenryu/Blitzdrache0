//! 状態を受けて返す処理の宣言の法則が、宣言を付け忘れた関数を反例として捕まえ、規則によらない書き換えの役割か遷移の役割の宣言で通ることを、
//! 原文から抽出したグラフで固定する試験。`Result` の中の状態を返す関数も捕まえることも固定する。
//! 規則のメソッド・自由関数・トレイトの本体と実装の形と、法則の前件に当たらない形は、子のモジュール `関数の置き場ごとの試験` が固定する。

use blitz_design_verification::{命題の検証器, 検証結果, 構造の検証器};

#[path = "状態を受けて返す処理の宣言の法則の試験/関数の置き場ごとの試験.rs"]
mod 関数の置き場ごとの試験;

use super::状態を受けて返す処理の宣言の法則::法則を組む;
use crate::設計関係のモデル::原文から設計関係グラフと抽出の欠けを組む;

const 型の宣言: &str = "pub struct 状態 {\n    番号: u8,\n}\n\nimpl M状態 for 状態 {}\n\npub struct 材料 {\n    値: u8,\n}\n\npub struct 規則 {\n    上限: u8,\n}\n\nimpl M規則 for 規則 {}\n\n";

const 関数: &str = "impl 状態 {\n    pub fn 書き換える(self, 材料: 材料) -> 状態 {\n        todo!()\n    }\n\n    pub fn 進める(self, 規則: &規則) -> 状態 {\n        todo!()\n    }\n\n    pub fn 番号(&self) -> u8 {\n        todo!()\n    }\n}\n\n";

const 書き換えの宣言: &str = "const _: M規則によらない書き換え関数<状態, 材料> = M規則によらない書き換え関数::生成する(状態::書き換える);\n";

const 遷移の宣言: &str = "const _: M規則で決まる遷移関数<状態, 規則> = M規則で決まる遷移関数::生成する(状態::進める);\n";

// 型の宣言の後ろへ関数と宣言を並べた原文から抽出したグラフで、法則を検証する。
fn 検証する(型の宣言の後ろに並べる原文一覧: &[&str]) -> 検証結果 {
    let 原文: String = [型の宣言].iter().chain(型の宣言の後ろに並べる原文一覧).copied().collect();
    let 抽出したもの = 原文から設計関係グラフと抽出の欠けを組む(&[("crates/blitz_game/src/試験.rs", 原文.as_str())]);
    構造の検証器::生成する(&抽出したもの.グラフ, 抽出したもの.関係を落とした抽出の欠落へ写す()).検証する(&法則を組む())
}

// 反証済みの結果の反例の割り当てに、パスがその末尾(`状態::書き換える` のような所有者の並びと関数の名前)で終わる処理が現れるか。
fn 反例に現れるか(結果: &検証結果, 処理の末尾: &str) -> bool {
    結果.反証済みの再現の材料().iter().any(|(_, 概念)| 概念.ends_with(&format!("::{処理の末尾}")))
}

#[test]
fn 宣言の無い書き換えと遷移は反例になる() {
    let 結果 = 検証する(&[関数]);
    assert!(結果.反証済みか(), "{}", 結果.表記());
    assert!(反例に現れるか(&結果, "状態::書き換える") || 反例に現れるか(&結果, "状態::進める"), "{:?}", 結果.反証済みの再現の材料());
}

#[test]
fn 書き換えだけに宣言が無ければ書き換えが反例になる() {
    let 結果 = 検証する(&[関数, 遷移の宣言]);
    assert!(結果.反証済みか(), "{}", 結果.表記());
    assert!(反例に現れるか(&結果, "状態::書き換える"), "{:?}", 結果.反証済みの再現の材料());
}

#[test]
fn 遷移だけに宣言が無ければ遷移が反例になる() {
    let 結果 = 検証する(&[関数, 書き換えの宣言]);
    assert!(結果.反証済みか(), "{}", 結果.表記());
    assert!(反例に現れるか(&結果, "状態::進める"), "{:?}", 結果.反証済みの再現の材料());
}

#[test]
fn 規則によらない書き換えの宣言と遷移の宣言があれば証明済みになる() {
    let 結果 = 検証する(&[関数, 書き換えの宣言, 遷移の宣言]);
    assert!(結果.証明済みか(), "{}", 結果.表記());
}

#[test]
fn 結果の型の中で状態を返す関数も捕まえる() {
    let 失敗しうる = "pub struct 失敗 {\n    理由: u8,\n}\n\nimpl 状態 {\n    pub fn 直す(&self, 材料: 材料) -> Result<状態, 失敗> {\n        todo!()\n    }\n}\n";
    let 結果 = 検証する(&[失敗しうる]);
    assert!(反例に現れるか(&結果, "状態::直す"), "{}", 結果.表記());
}
