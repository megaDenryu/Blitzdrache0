//! 構造の法則の命題の集合が問う答えを固定する試験。設計の検証の合否は、この答えを弱める欠落だけで不合格になる。
//! 関数の署名が語るプリミティブな関係(関連関数として持つ・引数に取る・返す)を問う公理はまだ無いため、その答えだけを弱める欠落は合否に効かない。

use blitz_design_verification::{プリミティブな関係の種類, 欠落が弱める答え, 設計関係の種類};

use super::super::構造の法則の命題の集合を組む;

#[test]
fn 公理は分類と消費と参照と生成と保持を問い関数の署名の関係を問わない() {
    let 問う答え一覧 = 構造の法則の命題の集合を組む().問う答え一覧();
    for 答え in [
        欠落が弱める答え::分類,
        欠落が弱める答え::設計関係(設計関係の種類::消費する),
        欠落が弱める答え::設計関係(設計関係の種類::参照する),
        欠落が弱める答え::設計関係(設計関係の種類::生成する),
        欠落が弱める答え::プリミティブな関係(プリミティブな関係の種類::保持する),
    ] {
        assert!(問う答え一覧.contains(&答え), "{答え:?} を問っていない: {問う答え一覧:?}");
    }
    for 種類 in [プリミティブな関係の種類::関連関数として持つ, プリミティブな関係の種類::引数に取る, プリミティブな関係の種類::返す] {
        assert!(!問う答え一覧.contains(&欠落が弱める答え::プリミティブな関係(種類)), "{種類:?} を問っている: {問う答え一覧:?}");
    }
}
