//! 構造の法則の命題の集合が問う答えを固定する試験。設計の検証の合否は、この答えを弱める欠落だけで不合格になる。
//! 状態を受けて返す処理の宣言の法則は全ての処理を量化し、処理の節点の並びはどの事実を落としても欠けうるため、全ての答えを問う。
//! したがって、関数の署名の関係(関連関数として持つ・受け手に取る・引数に取る・返す)の答えを弱める欠落も合否に効く。

use blitz_design_verification::欠落が弱める答え;

use super::super::構造の法則の命題の集合を組む;

#[test]
fn 法則の集合は全ての答えを問う() {
    let 問う答え一覧 = 構造の法則の命題の集合を組む().問う答え一覧();
    for 答え in 欠落が弱める答え::全部() {
        assert!(問う答え一覧.contains(&答え), "{答え:?} を問っていない: {問う答え一覧:?}");
    }
}
