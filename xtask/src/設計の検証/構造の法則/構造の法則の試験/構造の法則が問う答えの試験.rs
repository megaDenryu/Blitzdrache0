//! 構造の法則の命題の集合が問う答えを固定する試験。設計の検証の合否は、この答えを弱める欠落だけで不合格になる。
//! 存在理由の公理の6つは、マーカーを持つ型を量化し(分類)、処理が型を変換用の素材にするか参照するか生成するかを問い(設計関係の3語)、
//! 容器が型を持つ経路を問う(保持する)。したがって、この5つの答えだけを問い、関数の署名の関係(関連関数として持つ・受け手に取る・引数に取る・返すなど)と
//! 識別する・書き換えるの答えを弱める欠落は合否に効かない。

use blitz_design_verification::{プリミティブな関係の種類, 欠落が弱める答え, 関数の引数と戻り値の役目};

use super::super::構造の法則の命題の集合を組む;

#[test]
fn 法則の集合は存在理由の公理が使う5つの答えだけを問う() {
    let 問う答え一覧 = 構造の法則の命題の集合を組む().問う答え一覧();
    let 設計関係 = |役目: 関数の引数と戻り値の役目| 欠落が弱める答え::設計関係(役目.設計関係の結び付き方へ写す());
    let 期待 = [
        欠落が弱める答え::分類,
        設計関係(関数の引数と戻り値の役目::変換用の素材にする),
        設計関係(関数の引数と戻り値の役目::参照する),
        設計関係(関数の引数と戻り値の役目::生成する),
        欠落が弱める答え::プリミティブな関係(プリミティブな関係の種類::保持する),
    ];
    assert_eq!(問う答え一覧.len(), 期待.len(), "{問う答え一覧:?}");
    for 答え in 期待 {
        assert!(問う答え一覧.contains(&答え), "{答え:?} を問っていない: {問う答え一覧:?}");
    }
}
