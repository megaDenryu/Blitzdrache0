//! 存在理由の公理の試験が使う、公理のマーカーを名乗る対象の型1つと処理1つと容器の型1つだけを持つグラフを組む道具。
//! 対象の型が処理にどう使われるか(`使われ方`)だけを変えたグラフを組む。

use std::path::PathBuf;

use blitz_design_verification::{
    プリミティブな関係の種類, プリミティブな関係エッジ, マーカーの実装, 宣言の出どころ, 導出の根拠, 設計解釈マーカーの宣言の一覧, 設計関係エッジ, 関数の引数と戻り値の役目
};

use crate::設計関係のモデル::{抽出の出どころ, 抽出元の構文, 設計概念への参照, 設計概念ノード, 設計解釈マーカーの参照, 設計解釈マーカーの正本のモジュールパス, 設計関係グラフ};

const 型のモジュール: &str = "blitz_game::試験";
const 使うマーカー一覧: [&str; 7] = ["Mコマンド", "M規則", "M状態", "M解釈前の入力", "M命令の組", "Mイベント", "MParameter"];

/// 対象の型が処理にどう使われるか。処理が張る関係は、1つの処理が同時に張る関係の並びである(状態を変換用の素材にしかつ次の状態として生成する遷移を表すため)。
pub enum 使われ方 {
    使われない,
    処理が直に関係を張る(&'static [関数の引数と戻り値の役目]),
    容器に持たれる {
        容器のマーカー名: &'static str,
        容器への関係: &'static [関数の引数と戻り値の役目],
    },
}

fn 出どころ(構文: 抽出元の構文) -> 抽出の出どころ {
    抽出の出どころ {
        パス: PathBuf::from("crates/blitz_game/src/試験.rs"),
        行番号: 1,
        構文,
    }
}

fn 根拠() -> 導出の根拠 {
    導出の根拠::生成する("試験が定義の式を通さずに直に置いた関係", Vec::new())
}

fn 処理の関係(処理: &設計概念への参照, 役目: 関数の引数と戻り値の役目, 目的語: &設計概念への参照) -> 設計関係エッジ {
    設計関係エッジ {
        主語: 処理.clone(),
        結び付き方: 役目.設計関係の結び付き方へ写す(),
        目的語: 目的語.clone(),
        出どころ: 出どころ(抽出元の構文::関数の役割の型引数),
        根拠: 根拠(),
    }
}

fn 実装(型: &設計概念への参照, マーカー名: &'static str) -> マーカーの実装 {
    マーカーの実装 {
        型: 型.clone(),
        マーカー: 設計解釈マーカーの参照(マーカー名),
        出どころ: 宣言の出どころ {
            パス: PathBuf::from("crates/blitz_game/src/試験.rs"),
            行番号: 1,
        },
    }
}

// そのマーカーを名乗る対象の型を1つ持ち、その型を使われ方のとおりに処理へ結んだグラフ。
pub fn グラフ(マーカー名: &'static str, 使われ方: 使われ方) -> 設計関係グラフ {
    let 対象 = 設計概念ノード::型として生成する(型のモジュール, "対象の型");
    let 容器 = 設計概念ノード::型として生成する(型のモジュール, "容器の型");
    let 処理 = 設計概念ノード::処理として生成する(型のモジュール, "処理");
    let [対象の参照, 容器の参照, 処理の参照] = [&対象, &容器, &処理].map(設計概念ノード::参照を組む);
    let mut 概念一覧 = vec![対象, 容器, 処理];
    概念一覧.extend(使うマーカー一覧.map(|名前| 設計概念ノード::トレイトとして生成する(&設計解釈マーカーの正本のモジュールパス(), 名前)));
    let mut 実装一覧 = vec![実装(&対象の参照, マーカー名)];
    let (設計関係一覧, 保持する関係一覧) = match 使われ方 {
        使われ方::使われない => (Vec::new(), Vec::new()),
        使われ方::処理が直に関係を張る(種類一覧) => (種類一覧.iter().map(|種類| 処理の関係(&処理の参照, *種類, &対象の参照)).collect(), Vec::new()),
        使われ方::容器に持たれる { 容器のマーカー名, 容器への関係 } => {
            実装一覧.push(実装(&容器の参照, 容器のマーカー名));
            let 保持 = プリミティブな関係エッジ {
                主語: 容器の参照.clone(),
                種類: プリミティブな関係の種類::保持する,
                目的語: 対象の参照.clone(),
                出どころ: 出どころ(抽出元の構文::構造体のフィールド),
                根拠: 根拠(),
            };
            (容器への関係.iter().map(|種類| 処理の関係(&処理の参照, *種類, &容器の参照)).collect(), vec![保持])
        }
    };
    let 設計解釈マーカーの宣言の一覧 = 設計解釈マーカーの宣言の一覧::生成する(使うマーカー一覧.map(設計解釈マーカーの参照).to_vec(), 実装一覧, Vec::new());
    設計関係グラフ::生成する(概念一覧, 設計関係一覧, 保持する関係一覧, 設計解釈マーカーの宣言の一覧).グラフ
}
