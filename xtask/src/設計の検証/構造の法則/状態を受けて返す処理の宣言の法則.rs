//! 状態を受けて同じ状態を返す処理の宣言の法則(2026-09-28 のオーナー裁定)。`M状態` を名乗る型 s について、s を受け手に取るか引数に取り、
//! s をそのまま返す処理は、遷移の役割の宣言か、規則によらない書き換えの役割の宣言に包まれていることを求める。
//! そのまま返すとは、s を戻り値そのものとして返すか、`Result`・組・意味型の成分か `Box`・`Arc` の中身として返すことである。
//! s を `Vec`・`Option` の中や `impl Iterator<Item = s>` として返す関数(候補を並べる関数・次の値を順に渡す関数)は、状態の値そのものを返しておらず遷移でないため、前件に当たらない。
//! 境界付きの総称で状態を受けて返す関数(`fn f<S: M状態>(s: S) -> S`)は、型引数を境界のトレイト `M状態` として読むため状態の型を名指さず、量化の対象に入らない。
//!
//! 目的は、遷移の関数(ゲームの規則で状態を次の状態へ進める関数)に関数の役割の宣言を付け忘れたことを見つけることである。存在理由の公理は
//! 型の側から「その型を使う処理があるか」を問うため、同じ状態を別の宣言済みの遷移が使っていると、付け忘れた関数を見つけられない。
//! この法則は処理の側から、状態を受けて返す形の関数のどれにも宣言があるかを問う。
//!
//! 前件は関数の署名から導いたプリミティブな関係(受け手に取る・引数に取る・そのまま返す)で書き、後件は関数の役割の宣言から導いた設計の関係で書く。
//! 遷移の役割に包まれていることは、同じ処理が状態を消費しかつ次の状態として生成することで見分け(状態の存在理由の公理 A3 と同じ見分け方である)、
//! 規則によらない書き換えの役割に包まれていることは、処理が状態を書き換えることで見分ける。後件を「何かの役割の宣言に包まれている」と書かないのは、
//! 状態を消費するだけの役割(解釈の入力など)に包んだ関数を通さないためである。射影の役割の射影の型へ状態そのものを入れた宣言(`M射影関数<状態, 状態>`)は、
//! 状態を消費しかつ生成すると導かれ遷移と見分けられないため、`cargo xtask conform` が違反にする(`xtask/src/conform/射影関数の宣言の検査.rs`)。
//! 参照: `_doc/設計/設計オントロジー.md` 第8節。

use blitz_design_verification::{プリミティブな関係の種類, 原子命題, 命題, 対象集合, 束縛変数, 設計概念の種類, 設計関係の種類, 非空の命題一覧, 項};

/// この法則の名前。報告と試験が、この名前で法則を採る。
pub const 法則の名前: &str = "M状態を受け手か引数に取り同じM状態をそのまま返す処理は、遷移の役割か規則によらない書き換えの役割の宣言に包まれている";

/// 全ての状態と全ての処理について、処理がその状態を受けて返すなら、処理はその状態を遷移させるか書き換える、という全称の命題を組む。
pub fn 法則を組む() -> 命題 {
    let 状態 = 束縛変数::生成する("状態");
    let 処理 = 束縛変数::生成する("状態を受けて返す処理");
    let プリミティブ = |種類| {
        命題::原子から組む(原子命題::プリミティブな関係が在る {
            主語: 項::束縛変数(処理.clone()),
            種類,
            目的語: 項::束縛変数(状態.clone()),
        })
    };
    let 設計 = |種類| {
        命題::原子から組む(原子命題::設計関係が在る {
            主語: 項::束縛変数(処理.clone()),
            種類,
            目的語: 項::束縛変数(状態.clone()),
        })
    };
    let 受ける = 命題::選言(非空の命題一覧::先頭と残りから生成する(
        プリミティブ(プリミティブな関係の種類::受け手に取る),
        vec![プリミティブ(プリミティブな関係の種類::引数に取る)],
    ));
    let 前件 = 命題::連言(非空の命題一覧::先頭と残りから生成する(プリミティブ(プリミティブな関係の種類::そのまま返す), vec![受ける]));
    let 遷移させる = 命題::連言(非空の命題一覧::先頭と残りから生成する(設計(設計関係の種類::消費する), vec![設計(設計関係の種類::生成する)]));
    let 後件 = 命題::選言(非空の命題一覧::先頭と残りから生成する(遷移させる, vec![設計(設計関係の種類::書き換える)]));
    let 処理についての命題 = 命題::全称を組む(処理, 対象集合::種類で絞った設計概念(設計概念の種類::処理), 命題::含意を組む(前件, 後件));
    命題::全称を組む(状態, 対象集合::マーカーを持つ設計概念 { マーカー名: "M状態".to_string() }, 処理についての命題)
}
