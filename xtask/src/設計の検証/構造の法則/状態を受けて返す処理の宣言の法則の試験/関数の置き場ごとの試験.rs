// 反証: 状態を参照で受ける引数を `そのまま受け取る` に数えないと、`&状態` から新しい状態を組んで返す関数の付け忘れを見落とす。
// 実物の抽出器の経路で、参照の引数が `そのまま受け取る` になることを先に確かめる。
#[test]
