// 反証: `where` 句を読まないと、`where Self: B` で書いた上位トレイト(`trait A: B` と同じ意味)を落とす。
#[test]
fn where句で自分へ課した境界を上位トレイトとして読む() {
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[(正本のパス, "pub trait M旅程: M状態 where Self: Sized {}\n")]);
    let 表記一覧 = 設計解釈マーカーの宣言の表記一覧(&結果);
    for 期待 in [
        "blitz_design::設計解釈マーカー::M旅程 は blitz_design::設計解釈マーカー::M状態 を上位トレイトに持つ",
        "blitz_design::設計解釈マーカー::M旅程 は Sized を上位トレイトに持つ",
    ] {
        assert!(表記一覧.contains(&期待.to_string()), "{期待} が無い: {表記一覧:?}");
    }
    assert_eq!(結果.関係を落とした抽出の欠落へ写す().合計の件数(), 0, "{:?}", 抽出できなかった理由の説明一覧(&結果));
}

// 反証: 見出しの行だけを読むと、rustfmt が次の行以降へ折った上位トレイトと `where` 句を落とす。型引数への境界 `T: Clone` は上位トレイトではない。
#[test]
fn 次の行以降へ折った見出しの上位トレイトとwhere句で自分へ課した境界を読む() {
    let 原文 = "pub trait M旅程<T>:\n    M状態\nwhere\n    Self: M値オブジェクト,\n    T: Clone,\n{\n}\n";
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[(正本のパス, 原文)]);
    let 表記一覧 = 設計解釈マーカーの宣言の表記一覧(&結果);
    for 期待 in [
        "blitz_design::設計解釈マーカー::M旅程 は blitz_design::設計解釈マーカー::M状態 を上位トレイトに持つ",
        "blitz_design::設計解釈マーカー::M旅程 は blitz_design::設計解釈マーカー::M値オブジェクト を上位トレイトに持つ",
    ] {
        assert!(表記一覧.contains(&期待.to_string()), "{期待} が無い: {表記一覧:?}");
    }
    assert_eq!(表記一覧.len(), 2, "{表記一覧:?}");
    assert_eq!(結果.関係を落とした抽出の欠落へ写す().合計の件数(), 0, "{:?}", 抽出できなかった理由の説明一覧(&結果));
}

// 反証: 型引数の入れ子を読めないと、入れ子の型引数を持つトレイトの上位トレイトを落とす。寿命の境界はトレイトでないため上位トレイトに数えない。
