#[test]
fn 実物の失敗しない状態遷移関数は状態遷移パラメータを変換用の素材にし失敗の位置からは関係を導かない() {
    let 結果 = 実物のcratesから結果を組む();
    let 表記一覧 = super::抽出の試験の段取り::関係の表記一覧(&結果);
    let 主語 = "blitz_esca::居場所::旅行者の居場所::歩行を状態遷移させる";
    let 期待 = format!("{主語} 変換用の素材にする blitz_esca::transition_parameter::状態遷移パラメータ");
    assert!(表記一覧.contains(&期待), "{期待} が無い");
    let 生成する先一覧: Vec<&String> = 表記一覧.iter().filter(|表記| 表記.starts_with(&format!("{主語} 生成する "))).collect();
    assert!(生成する先一覧.iter().all(|表記| !表記.contains("Infallible")), "値を持たない失敗の型が生成する先のノードになった: {生成する先一覧:?}");
    assert!(
        生成する先一覧.iter().any(|表記| 表記.ends_with("旅行者の居場所") || 表記.ends_with("旅行者の出来事")),
        "失敗の位置を外したことで次の状態と出来事の生成まで落ちた: {生成する先一覧:?}"
    );
}
