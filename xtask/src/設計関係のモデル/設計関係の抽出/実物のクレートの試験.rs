//! リポジトリの実物の `crates` を走査する試験。
//!
//! 他の回帰試験が文字列として組んだソースを使うのは、実物が変わると構文と関係の対応の固定が壊れるためである。
//! ここでは、抽出器が実物のファイル配置と走査の経路で動くことと、実物に在る役割の使用箇所が受理され続けることと、
//! 実物のどの文字列も抽出器の保証範囲の外へ落ちないことを確かめる。
//! 実物で確かめるのは、受理する正規形を狭く書き下した条件が実物の文字列を落とさないことを、文字列の模型では保証できないためである。
//! 保証範囲の外が0件であることは `cargo xtask conform` の `抽出器が受理する正規形の検査` が違反として落とす条件と同じであり、この試験がその偽の違反の不在を先に示す。
//!
//! 走査のルートを`CARGO_MANIFEST_DIR`から組むのは、試験の実行時の作業ディレクトリがxtaskのパッケージであり、`crates`の相対パスが解決しないためである。

use std::path::PathBuf;

use super::抽出の成果と欠け::抽出した設計関係グラフと抽出の欠け;
use super::抽出対象のソース群の定義::抽出対象のソース群;
use crate::file_scan;
use crate::設計関係のモデル::設計概念の識別用情報;

// 実物の `crates` を走査して抽出の結果を組む。
fn 実物のcratesから結果を組む() -> 抽出した設計関係グラフと抽出の欠け {
    let ルート = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("..").join("crates");
    let Some(ルートの表記) = ルート.to_str().map(str::to_string) else {
        panic!("走査のルートのパスを文字列として読めない: 不変条件「リポジトリのパスはUTF-8である」が破れた");
    };
    let パス一覧 = match file_scan::対象ファイル一覧を集める(&[&ルートの表記], &["rs"]) {
        Ok(パス一覧) => パス一覧,
        Err(破れ) => panic!("実物のcratesを走査できなかった: {破れ}"),
    };
    let mut 原文一覧 = Vec::new();
    for パス in パス一覧.into_iter().filter(|パス| パス.components().any(|部品| 部品.as_os_str() == "src")) {
        match std::fs::read_to_string(&パス) {
            Ok(原文) => 原文一覧.push((パス, 原文)),
            Err(誤り) => panic!("実物のソースを読めなかった: {} {誤り}", パス.display()),
        }
    }
    assert!(!原文一覧.is_empty(), "実物のcratesのソースが1件も集まらなかった: {ルートの表記}");
    super::抽出の入口::ソース群から抽出する(&抽出対象のソース群::原文一覧から生成する(原文一覧))
}

#[test]
fn 実物のcratesを走査するとマーカーの実装が出て付いているマーカーが上位トレイトの宣言で閉じる() {
    let 結果 = 実物のcratesから結果を組む();
    let 表記一覧: Vec<String> = 結果.グラフ.各型に付いているマーカーの一覧を貸す().設計解釈マーカーの宣言の一覧を貸す().マーカーの実装一覧().iter().map(|実装| 実装.表記()).collect();
    assert!(
        表記一覧.contains(&"blitz_esca::居場所::旅行者の居場所 は blitz_design::設計解釈マーカー::M状態 を実装する".to_string()),
        "実物の `impl M状態 for 旅行者の居場所` から宣言が出ていない: {}件",
        表記一覧.len()
    );
    let 居場所 = 設計概念の識別用情報::型として生成する("blitz_esca::居場所", "旅行者の居場所");
    let 不変データ = 設計概念の識別用情報::トレイトとして生成する("blitz_design::設計解釈マーカー", "M不変データ");
    assert!(
        結果.グラフ.各型に付いているマーカーの一覧を貸す().付いているマーカーがトレイトを含むか(&居場所, &不変データ),
        "実物の `trait M状態: M不変データ` で付いているマーカーが閉じていない"
    );
}

#[test]
fn 実物の3件の役割の使用箇所は受理の条件を満たし処理のノードになる() {
    let 結果 = 実物のcratesから結果を組む();
    let 表記一覧: Vec<String> = 結果.グラフ.概念一覧().iter().map(|概念| 概念.識別子().表記()).collect();
    for 期待 in [
        "blitz_esca::キーボードの入力::キーボード歩行入力::歩行入力を解釈する",
        "blitz_esca::居場所::旅行者の居場所::歩行を状態遷移させる",
        "blitz_esca::居場所::旅行者の居場所::描画位置を射影する",
    ] {
        assert!(表記一覧.iter().any(|表記| 表記 == 期待), "{期待} が処理のノードとして立っていない");
    }
}

