//! 抽出の規則6(関数の署名)の回帰試験。「このRustの構文からこの関数の署名の事実が出る」と、項目の位置でない関数を黙って外さないことと、
//! 関数の役割の宣言が包んだ関数とその関数の署名の事実が同じ節点になることを固定する。

use super::抽出の成果と欠け::抽出した設計関係グラフと抽出の欠け;
use super::抽出の試験の段取り::{原文から設計関係グラフと抽出の欠けを組む, 抽出できなかった理由の説明一覧};
use crate::設計関係のモデル::設計概念の種類;
use blitz_design_verification::{受け手の種類, 設計概念への参照, 関数の所有者, 関数の署名の事実};

const 旅行者のパス: &str = "crates/blitz_esca/src/旅行者.rs";

fn 抽出する(原文: &str) -> 抽出した設計関係グラフと抽出の欠け {
    原文から設計関係グラフと抽出の欠けを組む(&[(旅行者のパス, 原文)])
}

// 名前で関数の署名の事実を1件探す。見つからなければ試験の段取りが誤っている。
fn 署名<'a>(結果: &'a 抽出した設計関係グラフと抽出の欠け, 名前: &str) -> &'a 関数の署名の事実 {
    let Some(署名) = 結果.事実.関数の署名一覧.iter().find(|署名| 署名.処理.識別子().名前 == 名前) else {
        panic!("関数 {名前} の署名の事実が無い: {:?}", 結果.事実.関数の署名一覧);
    };
    署名
}

fn 引数の書かれた文字列一覧(署名: &関数の署名の事実) -> Vec<&str> {
    署名.引数の表記一覧.iter().map(|表記| 表記.書かれた文字列()).collect()
}

#[test]
fn 実装の本体の関数は型を所有者に持ち自分の型の予約語を対象の型へ置き換える() {
    let 原文 = "pub struct 旅行者の現在地 {\n    東: f32,\n}\n\nimpl 旅行者の現在地 {\n    pub fn 動かす(self, 意図: &旅行者の意図, 秒: f32) -> Result<Self, 失敗> {\n        todo!()\n    }\n\n    fn 読む(&self) -> u8 {\n        1\n    }\n}\n";
    let 結果 = 抽出する(原文);
    let 動かす = 署名(&結果, "動かす");
    assert_eq!(動かす.処理.識別子().表記(), "blitz_esca::旅行者::旅行者の現在地::動かす");
    assert!(matches!(&動かす.所有者, 関数の所有者::型(表記) if 表記.書かれた文字列() == "旅行者の現在地"), "{:?}", 動かす.所有者);
    assert_eq!(動かす.受け手, 受け手の種類::値);
    assert_eq!(引数の書かれた文字列一覧(動かす), vec!["&旅行者の意図", "f32"]);
    assert_eq!(動かす.戻り値の表記.as_ref().map(|表記| 表記.書かれた文字列()), Some("Result<旅行者の現在地, 失敗>"));
    assert_eq!(署名(&結果, "読む").受け手, 受け手の種類::参照);
}

#[test]
fn トレイトの本体の関数はトレイトを所有者に持ち自分の型の予約語を型引数に数える() {
    let 結果 = 抽出する("pub trait 世界の形 {\n    fn 尋ねる(&mut self, 問い: 掃引の問い) -> Self;\n}\n");
    let 尋ねる = 署名(&結果, "尋ねる");
    let 期待 = 設計概念への参照::Rustの項目として生成する(
        crate::設計関係のモデル::設計概念の識別子::Rustの項目として生成する("blitz_esca::旅行者", "世界の形"),
        crate::設計関係のモデル::Rustの項目の種類::トレイト,
    );
    assert_eq!(尋ねる.所有者, 関数の所有者::トレイト(期待));
    assert_eq!(尋ねる.受け手, 受け手の種類::可変参照);
    assert!(尋ねる.戻り値の表記.as_ref().is_some_and(|表記| 表記.書かれた文字列() == "Self" && 表記.有効な型引数名一覧().contains(&"Self".to_string())));
}

#[test]
fn 複数の行にまたがる自由関数の見出しを型引数と境界の句ごと読む() {
    let 原文 = "pub fn 合わせる<T: Clone>(\n    左: T,\n    右: &[旅行者の現在地],\n) -> Vec<T>\nwhere\n    T: Clone,\n{\n    todo!()\n}\n";
    let 結果 = 抽出する(原文);
    let 合わせる = 署名(&結果, "合わせる");
    assert_eq!(合わせる.所有者, 関数の所有者::自由関数);
    assert_eq!(合わせる.受け手, 受け手の種類::無し);
    assert_eq!(引数の書かれた文字列一覧(合わせる), vec!["T", "&[旅行者の現在地]"]);
    assert!(合わせる.引数の表記一覧[0].有効な型引数名一覧().contains(&"T".to_string()));
    assert_eq!(合わせる.戻り値の表記.as_ref().map(|表記| 表記.書かれた文字列()), Some("Vec<T>"));
}

#[test]
fn 関数の本体の中の関数は署名の事実にせず項目の位置でない関数として数える() {
    let 結果 = 抽出する("pub fn 外側() {\n    fn 内側(値: u8) -> u8 {\n        値\n    }\n}\n");
    assert!(結果.事実.関数の署名一覧.iter().all(|署名| 署名.処理.識別子().名前 != "内側"), "{:?}", 結果.事実.関数の署名一覧);
    assert!(
        抽出できなかった理由の説明一覧(&結果).iter().any(|説明| 説明.contains("`内側` は関数の本体などの項目の位置でない")),
        "{:?}",
        抽出できなかった理由の説明一覧(&結果)
    );
}

// 反証: 署名の事実の処理を別の組み方で作ると、役割の宣言が包んだ関数と同じ関数が2つの節点へ割れる。
#[test]
fn 関数の役割の宣言が包んだ関数と関数の署名の事実は同じ節点になる() {
    let 原文 = "pub struct キーボード歩行入力 {\n    前: bool,\n}\n\npub enum 旅行者の意図 {\n    静止,\n}\n\nimpl キーボード歩行入力 {\n    pub fn 歩行入力を解釈する(&self) -> 旅行者の意図 {\n        旅行者の意図::静止\n    }\n}\n\nconst _: M解釈関数<キーボード歩行入力, 旅行者の意図> = M解釈関数::生成する(キーボード歩行入力::歩行入力を解釈する);\n";
    let 結果 = 抽出する(原文);
    assert_eq!(結果.事実.関数の役割の宣言一覧[0].処理, 署名(&結果, "歩行入力を解釈する").処理);
    let 処理の節点の数 = 結果.グラフ.概念一覧().iter().filter(|概念| 概念.種類() == 設計概念の種類::処理).count();
    assert_eq!(処理の節点の数, 1, "{:?}", 結果.グラフ.概念一覧());
}

#[test]
fn 関数の署名から関連関数として持つと引数に取ると返すが導かれ設計の関係は導かれない() {
    let 原文 = "pub struct 旅行者の現在地 {\n    東: f32,\n}\n\npub struct 旅行者の意図 {\n    北: f32,\n}\n\nimpl 旅行者の現在地 {\n    pub fn 動かす(&self, 意図: &旅行者の意図) -> 旅行者の現在地 {\n        todo!()\n    }\n}\n";
    let 結果 = 抽出する(原文);
    let 表記一覧 = super::抽出の試験の段取り::関係の表記一覧(&結果);
    let 処理 = "blitz_esca::旅行者::旅行者の現在地::動かす";
    for 期待 in [
        format!("blitz_esca::旅行者::旅行者の現在地 関連関数として持つ {処理}"),
        format!("{処理} 引数に取る blitz_esca::旅行者::旅行者の意図"),
        format!("{処理} 返す blitz_esca::旅行者::旅行者の現在地"),
    ] {
        assert!(表記一覧.contains(&期待), "{期待} が無い: {表記一覧:?}");
    }
    assert!(結果.グラフ.関係一覧().is_empty(), "関数の署名から設計の関係を導いた: {:?}", 結果.グラフ.関係一覧());
}

// 反証: 行の途中の `fn` を数えないと、1行に書いたトレイトの本体の関数が黙って署名の事実から外れ、関数の署名の答えを弱めない。
#[test]
fn 行の途中の関数の見出しは署名の事実にせず関数の署名を読めなかった行として数える() {
    let 結果 = 抽出する("pub trait 読める { fn 読む(&self); }\n");
    assert!(結果.事実.関数の署名一覧.iter().all(|署名| 署名.処理.識別子().名前 != "読む"), "{:?}", 結果.事実.関数の署名一覧);
    let 行一覧: Vec<_> = 結果.抽出できなかった行一覧.iter().filter(|行| 行.理由.説明().contains("`読む` の関数の見出しが行の頭に無く")).collect();
    assert_eq!(行一覧.len(), 1, "{:?}", 抽出できなかった理由の説明一覧(&結果));
    assert!(行一覧[0].関数の署名を読めなかった行か(), "行の途中の関数の見出しが関数の署名を読めなかった区分に入っていない");
}
