//! 関数の署名が導く関係の端点が、ほかの規則が立てる節点と同じ節点になることを固定する回帰試験。
//! 端点が別の節点へ割れると、同じ概念の辺が2つの節点へ散り、片方への問いが辺の不在を答える。

use super::抽出の成果と欠け::抽出した設計関係グラフと抽出の欠け;
use super::抽出の試験の段取り::{原文から設計関係グラフと抽出の欠けを組む, 関係の表記一覧};
use crate::設計関係のモデル::設計概念の種類;

const 旅行者のパス: &str = "crates/blitz_esca/src/旅行者.rs";

fn 抽出する(原文: &str) -> 抽出した設計関係グラフと抽出の欠け {
    原文から設計関係グラフと抽出の欠けを組む(&[(旅行者のパス, 原文)])
}

// その名前とその種類の節点の、モジュールパスの一覧。
fn 節点のモジュールパス一覧(結果: &抽出した設計関係グラフと抽出の欠け, 名前: &str, 種類: 設計概念の種類) -> Vec<String> {
    結果
        .グラフ
        .概念一覧()
        .iter()
        .filter(|概念| 概念.識別子().名前 == 名前 && 概念.種類() == 種類)
        .map(|概念| 概念.識別子().モジュールパス.clone())
        .collect()
}

// 反証: 定義の探索の口が `struct`・`enum` しか探さないと、`dyn 世界の形` の目的語は定義をたどれない空の節点になり、トレイトの本体の関数の所有者の節点と割れる。
#[test]
fn dynの目的語は定義をたどれたトレイトの節点になる() {
    let 結果 = 抽出する("pub trait 世界の形 {\n    fn 尋ねる(&self);\n}\n\npub fn 使う(口: &dyn 世界の形) {}\n");
    let 表記一覧 = 関係の表記一覧(&結果);
    assert!(表記一覧.contains(&"blitz_esca::旅行者::使う 引数に取る blitz_esca::旅行者::世界の形".to_string()), "{表記一覧:?}");
    assert_eq!(節点のモジュールパス一覧(&結果, "世界の形", 設計概念の種類::トレイト), vec!["blitz_esca::旅行者".to_string()]);
}

// 反証: 所有者の型の表記を署名の読み方で読むと、`Vec<中身>` の包みを剥がし、組を2つの型へ分けて、`中身` がどちらの実装の関数も関連関数として持つことになる。
#[test]
fn 実装の対象の型を包みを剥がさず1つの型として持ち主にする() {
    let 結果 = 抽出する("pub struct 中身 {\n    値: f32,\n}\n\npub trait 読める {\n    fn 読む(&self);\n}\n\nimpl 読める for Vec<中身> {\n    fn 読む(&self) {}\n}\n\nimpl 読める for (中身, 中身) {\n    fn 読む(&self) {}\n}\n");
    let 表記一覧 = 関係の表記一覧(&結果);
    assert!(!表記一覧.iter().any(|表記| 表記.starts_with("blitz_esca::旅行者::中身 関連関数として持つ")), "{表記一覧:?}");
    assert!(表記一覧.iter().any(|表記| 表記.starts_with("Vec 関連関数として持つ")), "{表記一覧:?}");
}

// 反証: 自由関数の識別子を型と同じ名前空間に置くと、同じモジュールの同じ名前の型と自由関数が同じ識別子になり、同一性の衝突が全部の答えを弱める。
#[test]
fn 同じ名前の型と自由関数は衝突しない() {
    let 結果 = 抽出する("pub struct 旅行者 {\n    東: f32,\n}\n\npub fn 旅行者() {}\n");
    assert!(結果.同一性の衝突一覧.is_empty(), "{:?}", 結果.同一性の衝突一覧);
    assert_eq!(節点のモジュールパス一覧(&結果, "旅行者", 設計概念の種類::処理).len(), 1);
}

// 反証: トレイトの実装の関数の所有者の並びを対象の型の名前だけにすると、固有の実装の同じ名前の関数と1つの節点へまとまる。
#[test]
fn 固有の実装とトレイトの実装の同じ名前の関数は別の節点になる() {
    let 原文 = "pub struct 旅行者 {\n    東: f32,\n}\n\nimpl 旅行者 {\n    pub fn 表示する(&self) {}\n}\n\nimpl 表示できる<u8> for 旅行者 {\n    fn 表示する(&self) {}\n}\n\nimpl 表示できる<u16> for 旅行者 {\n    fn 表示する(&self) {}\n}\n";
    let 結果 = 抽出する(原文);
    let 表記一覧: Vec<String> = 結果.事実.関数の署名一覧.iter().map(|署名| 署名.処理.識別子().表記()).collect();
    assert_eq!(
        表記一覧,
        vec![
            "blitz_esca::旅行者::旅行者::表示する".to_string(),
            "blitz_esca::旅行者::旅行者::表示できる<u8>::表示する".to_string(),
            "blitz_esca::旅行者::旅行者::表示できる<u16>::表示する".to_string(),
        ]
    );
    assert_eq!(節点のモジュールパス一覧(&結果, "表示する", 設計概念の種類::処理).len(), 3);
}
