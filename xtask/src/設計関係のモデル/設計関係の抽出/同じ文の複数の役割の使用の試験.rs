//! 1つの文に関数の役割の使用が2つ以上ある文の回帰試験。抽出器が最初の1つだけを読んで残りを黙って消さず、
//! 文全体を保証範囲の外の構文として関係を落とした抽出の欠落に数えることを固定する。1行に書いた文と、rustfmt が折った文を繋いだ文の両方を見る。

use super::保証範囲の外の構文の定義::保証範囲の外の構文;
use super::抽出の試験の段取り::{原文から設計関係グラフと抽出の欠けを組む, 役割の使用箇所の試験が使う型の定義, 抽出できなかった理由の説明一覧, 関係の表記一覧};

const 移動のパス: &str = "crates/blitz_esca/src/traveler_movement.rs";

/// 反証: 役割の一覧の順に最初に見つかった使用だけを読むと、2つ目の使用は関係にも抽出できなかった行にも現れず、黙って消える。
#[test]
fn 同じ文に役割の使用が2つある文は黙って落とさず欠落として数える() {
    let 一行の文 = "const _: (M射影関数<旅行者の現在地, 旅行者の出来事>, M解釈関数<キーボード歩行入力, 旅行者の意図>) = (M射影関数::生成する(旅行者の現在地::射影する), M解釈関数::生成する(キーボード歩行入力::歩行入力を解釈する));\n";
    let 折れた文 = "const _: (M射影関数<旅行者の現在地, 旅行者の出来事>,\n    M解釈関数<キーボード歩行入力, 旅行者の意図>) =\n    (M射影関数::生成する(旅行者の現在地::射影する), M解釈関数::生成する(キーボード歩行入力::歩行入力を解釈する));\n";
    for 文 in [一行の文, 折れた文] {
        let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[(移動のパス, &(役割の使用箇所の試験が使う型の定義() + 文))]);
        let 欠落 = 結果.関係を落とした抽出の欠落へ写す();
        assert_eq!(欠落.合計の件数(), 1, "{}", 欠落.説明());
        let 構文一覧: Vec<&保証範囲の外の構文> = 結果.抽出できなかった行一覧().iter().filter_map(|行| 行.理由().保証範囲の外の構文を採る()).collect();
        assert_eq!(構文一覧, vec![&保証範囲の外の構文::同じ文に役割の使用が複数ある { 使用の数: 2 }], "{:?}", 抽出できなかった理由の説明一覧(&結果));
        assert!(!関係の表記一覧(&結果).iter().any(|表記| 表記.contains("射影する") || 表記.contains("歩行入力を解釈する")), "{:?}", 関係の表記一覧(&結果));
    }
}
