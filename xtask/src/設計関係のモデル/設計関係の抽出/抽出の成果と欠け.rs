use super::抽出できなかった理由の区分の定義::{ソースで読めなかった宣言, 抽出できなかった理由の区分};
use super::抽出できなかった行の定義::{抽出できなかった行, 読めなかった箇所};
use crate::設計関係のモデル::同一性の衝突;
use crate::設計関係のモデル::設計関係グラフ;
use blitz_design_verification::{プリミティブな宣言, 定義の式, 欠落が弱める答え, 落とした理由ごとの件数, 設計関係の抽出漏れ};

pub use 抽出の成果の定義::抽出の成果;

/// 抽出器が返す答え。グラフと、抽出できなかった行の一覧と、同一性の衝突の一覧と、関係を導いたプリミティブな宣言である。
/// 宣言を運ぶのは、射影関数の宣言の検査が、どの役割の宣言から関係を導いたかをグラフのエッジでなく宣言から読むためである。
#[derive(Debug, Clone, Default)]
pub struct 抽出した設計関係グラフと抽出の欠け {
    グラフ: 設計関係グラフ,
    プリミティブな宣言: プリミティブな宣言,
    抽出できなかった行一覧: Vec<抽出できなかった行>,
    同一性の衝突一覧: Vec<同一性の衝突>,
}

impl 抽出した設計関係グラフと抽出の欠け {
    /// 組んだグラフと、関係を導いたプリミティブな宣言と、抽出できなかった行と、同一性の衝突から組む。抽出の成果だけがこれを呼ぶ。
    fn 生成する(グラフ: 設計関係グラフ, プリミティブな宣言: プリミティブな宣言, 抽出できなかった行一覧: Vec<抽出できなかった行>, 同一性の衝突一覧: Vec<同一性の衝突>) -> Self {
        Self {
            グラフ,
            プリミティブな宣言,
            抽出できなかった行一覧,
            同一性の衝突一覧,
        }
    }

    /// 組んだ設計関係グラフを読む。
    pub fn グラフ(&self) -> &設計関係グラフ {
        &self.グラフ
    }

    /// 関係を導いたプリミティブな宣言を読む。
    pub fn プリミティブな宣言(&self) -> &プリミティブな宣言 {
        &self.プリミティブな宣言
    }

    /// 抽出できなかった行の一覧を読む。
    pub fn 抽出できなかった行一覧(&self) -> &[抽出できなかった行] {
        &self.抽出できなかった行一覧
    }

    /// 同じ識別子へ種類の違う概念が来た同一性の衝突の一覧を読む。
    pub fn 同一性の衝突一覧(&self) -> &[同一性の衝突] {
        &self.同一性の衝突一覧
    }

    /// 検証器へ渡す設計関係の抽出漏れへ写す。設計関係を抽出し漏らした行だけを、種別の呼び名と弱める答えの並びの組ごとに数える。
    /// 呼び名だけでまとめないのは、同じ呼び名でも欠けた規則が違えば弱める答えが違い、答えの和を1件に持たせると、
    /// ある答えの未決定の理由の件数に、その答えを弱めない行まで入るためである。
    ///
    /// 識別子のモジュールパスだけが求まっていない行と明示して除外した行を数えないのは、どちらも設計関係を失っていないためである。識別子のモジュールパスだけが求まっていない行はエッジをグラフへ入れているが、
    /// そのエッジの端点は定義をたどれた型のノードではなく、同じ名前でモジュールパスが空の別のノードである。空のノードに触れた問いと、同じ名前の空のノードが在る
    /// 定義の型のノードへの問いは、構造の検証器が `未決定の理由::型の定義のモジュールパスが求まっていない` で別に止める。
    /// 設計概念でないため明示して除外した行はその位置に設計関係を初めから持たない。数えると、不在を根拠にしてよい問いまで未決定へ倒れ、検証器が何も答えられなくなる。
    /// ただし規則の本体の途中の変数(経由する概念と付いているマーカーを問う変数)の定義をたどれない欠けは、空のノードでは本体が成り立たずにエッジごと落ち、問いの両端のどちらにも同じ名前の空のノードが
    /// 無いことがあるため、構造の検証器の止めが効かないことがある。この行は4つ目の区分(定義の式の規則の本体で関係ごと落とした)へ属し、区分が持つ頭の関係の答えを弱める。
    ///
    /// 行が弱める答えは、欠けた箇所で決まる。定義の式の規則の本体で読めなかった行はその規則の頭の関係の答えだけを、
    /// ソースの構文を読めなかった行はその宣言を本体で読む規則の頭の答え(定義の式が答える)を、モジュールを丸ごと読めなかった行は全部の答えを弱める。
    /// 同一性の衝突は `設計関係の抽出漏れ::生成する` が数える。ノードが2つへ割れるとエッジが割れた両方へ散り、
    /// 片方へ問うと在るはずのエッジが見つからないため、設計関係を抽出し漏らしたのと同じ帰結になる。
    pub fn 設計関係の抽出漏れへ写す(&self) -> 設計関係の抽出漏れ {
        let 定義 = 定義の式::設計の関係とプリミティブな関係の定義();
        let mut 種別ごと: Vec<(&str, Vec<欠落が弱める答え>, usize)> = Vec::new();
        for 行 in &self.抽出できなかった行一覧 {
            let 弱める答え一覧 = match (行.理由().区分(), 行.読めなかった箇所()) {
                (抽出できなかった理由の区分::識別子のモジュールパスだけが求まっていない | 抽出できなかった理由の区分::設計概念でないため明示して除外した, _) => continue,
                (抽出できなかった理由の区分::定義の式の規則の本体で関係ごと落とした(導けなかった関係), _) | (抽出できなかった理由の区分::設計関係そのものを抽出できなかった(_), 読めなかった箇所::定義の式の規則の本体 { 導けなかった関係 }) =>
                {
                    vec![欠落が弱める答え::規則の頭から求める(導けなかった関係)]
                }
                (抽出できなかった理由の区分::設計関係そのものを抽出できなかった(ソースで読めなかった宣言::ある種類の宣言(種類)), 読めなかった箇所::ソースの構文) => {
                    定義.落とした宣言が弱める答え一覧(種類)
                }
                (抽出できなかった理由の区分::設計関係そのものを抽出できなかった(ソースで読めなかった宣言::モジュールの全部), 読めなかった箇所::ソースの構文) => {
                    欠落が弱める答え::全部()
                }
            };
            let 呼び名 = 行.理由().種別の呼び名();
            match 種別ごと.iter_mut().find(|(説明, 答え一覧, _)| *説明 == 呼び名 && *答え一覧 == 弱める答え一覧) {
                Some((_, _, 件数)) => *件数 += 1,
                None => 種別ごと.push((呼び名, 弱める答え一覧, 1)),
            }
        }
        let 理由ごとの件数 = 種別ごと.into_iter().map(|(説明, 答え一覧, 件数)| 落とした理由ごとの件数::生成する(説明.to_string(), 件数, 答え一覧)).collect();
        設計関係の抽出漏れ::生成する(理由ごとの件数, &self.同一性の衝突一覧).グラフの端点を検査する(&self.グラフ)
    }
}
