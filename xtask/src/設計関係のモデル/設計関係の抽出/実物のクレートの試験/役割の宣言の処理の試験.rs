//! 実物のクレートで、関数の役割の宣言が包んだ処理が、どれも関数の署名の事実の処理のどれかと同じ節点であることを固定する試験。
//! 1つでも外れると、その関数は役割の宣言と署名とで2つの処理の節点へ割れており、役割が導く設計関係と署名が導く関係が別の節点に付いている。

use super::実物のcratesから結果を組む;

#[test]
fn 実物の役割の宣言の処理はどれも関数の署名の事実の処理である() {
    let 結果 = 実物のcratesから結果を組む();
    let 外れた処理一覧: Vec<String> = 結果
        .事実
        .関数の役割の宣言一覧
        .iter()
        .filter(|宣言| !結果.事実.関数の署名一覧.iter().any(|署名| 署名.処理 == 宣言.処理))
        .map(|宣言| 宣言.処理.識別子().表記())
        .collect();
    assert!(外れた処理一覧.is_empty(), "関数の署名の事実と別の節点になった役割の宣言の処理: {外れた処理一覧:?}");
}
