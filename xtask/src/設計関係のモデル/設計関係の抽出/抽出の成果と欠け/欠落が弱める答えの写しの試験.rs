// 反証: 呼び名だけでまとめると、保持するの答えの未決定の理由に、変換用の素材にするの規則で読めなかった行まで数える。
#[test]
fn 同じ呼び名でも弱める答えが違う行は別の件に数える() {
    let 抽出したもの = 抽出した設計関係グラフと抽出の欠け {
        抽出できなかった行一覧: vec![
            修飾のある表記を読めなかった行(頭の関係::プリミティブな関係(プリミティブな関係の種類::保持する), 2),
            修飾のある表記を読めなかった行(頭の関係::プリミティブな関係(プリミティブな関係の種類::保持する), 3),
            修飾のある表記を読めなかった行(頭の関係::設計関係(関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す()), 4),
        ],
        ..抽出した設計関係グラフと抽出の欠け::default()
    };
    let 欠落 = 抽出したもの.設計関係の抽出漏れへ写す();
    let 保持するの説明 = 欠落.答えを弱める件の説明(&[欠落が弱める答え::プリミティブな関係(プリミティブな関係の種類::保持する)]);
    assert!(保持するの説明.contains("型の表記にパスの修飾がある: 2件"), "{保持するの説明}");
    let 変換用の素材にするの説明 = 欠落.答えを弱める件の説明(&[変換用の素材にする]);
    assert!(変換用の素材にするの説明.contains("型の表記にパスの修飾がある: 1件"), "{変換用の素材にするの説明}");
    assert_eq!(欠落.合計の件数(), 3);
}
