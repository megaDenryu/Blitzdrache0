//! 抽出の成果とは、抽出の規則1つぶんが読んだ途中の値のことである。概念と、プリミティブな宣言と、設計解釈マーカーの宣言の一覧の材料と、抽出できなかった行を持つ。
//! 規則は自分の成果へ足し、入口が規則を跨いで併せ、最後に設計関係グラフと抽出の欠けへ組む。成果だけが足す操作を持ち、組んだ答えは足す操作を持たない。

use super::super::marker_concept::設計解釈マーカーの参照一覧;
use super::super::抽出できなかった行の定義::抽出できなかった行;
use super::super::抽出対象のソース群の定義::抽出対象のソース群;
use super::抽出した設計関係グラフと抽出の欠け;
use crate::設計関係のモデル::{設計概念ノード, 設計関係グラフ};
use blitz_design_verification::{
    エンティティの識別子の関連型の宣言, フィールドの型の表記の宣言, プリミティブな宣言, マーカーの実装, 上位トレイトの宣言, 型の定義, 定義の式, 設計解釈マーカーの宣言の一覧, 関数の役割の宣言
};

/// 抽出の規則1つぶんの成果。
#[derive(Debug, Clone, Default)]
pub struct 抽出の成果 {
    概念一覧: Vec<設計概念ノード>, // 設計解釈マーカーの宣言の一覧の端点のノード
    プリミティブな宣言: プリミティブな宣言,
    マーカーの実装一覧: Vec<マーカーの実装>,
    上位トレイトの宣言一覧: Vec<上位トレイトの宣言>,
    抽出できなかった行一覧: Vec<抽出できなかった行>,
}

impl 抽出の成果 {
    /// 設計解釈マーカーの宣言の一覧の端点のノードを足す。
    pub fn 概念一覧を足す(&mut self, 概念一覧: impl IntoIterator<Item = 設計概念ノード>) {
        self.概念一覧.extend(概念一覧);
    }

    /// 抽出できなかった行を足す。
    pub fn 抽出できなかった行一覧を足す(&mut self, 行一覧: impl IntoIterator<Item = 抽出できなかった行>) {
        self.抽出できなかった行一覧.extend(行一覧);
    }

    /// マーカーの実装を1件足す。
    pub fn マーカーの実装を足す(&mut self, マーカーの実装: マーカーの実装) {
        self.マーカーの実装一覧.push(マーカーの実装);
    }

    /// 上位トレイトの宣言を1件足す。
    pub fn 上位トレイトの宣言を足す(&mut self, 上位トレイトの宣言: 上位トレイトの宣言) {
        self.上位トレイトの宣言一覧.push(上位トレイトの宣言);
    }

    /// 型の定義を1件足す。
    pub fn 型の定義を足す(&mut self, 型の定義: 型の定義) {
        self.プリミティブな宣言.型の定義を足す(型の定義);
    }

    /// フィールドの型の表記の宣言を1件足す。
    pub fn フィールドの型の表記を足す(&mut self, 宣言: フィールドの型の表記の宣言) {
        self.プリミティブな宣言.フィールドの型の表記を足す(宣言);
    }

    /// エンティティの識別子の関連型の宣言を1件足す。
    pub fn エンティティの識別子の関連型を足す(&mut self, 宣言: エンティティの識別子の関連型の宣言) {
        self.プリミティブな宣言.エンティティの識別子の関連型を足す(宣言);
    }

    /// 関数の役割の宣言を1件足す。
    pub fn 関数の役割の宣言を足す(&mut self, 宣言: 関数の役割の宣言) {
        self.プリミティブな宣言.関数の役割の宣言を足す(宣言);
    }

    /// 他の規則の成果を自分の後ろへ併せる。重複と種類の食い違いはここでは見ず、グラフの組み立てが重複のまとめと衝突の検出を行う。
    pub fn 併せる(&mut self, 他: Self) {
        self.概念一覧.extend(他.概念一覧);
        self.プリミティブな宣言.併せる(他.プリミティブな宣言);
        self.マーカーの実装一覧.extend(他.マーカーの実装一覧);
        self.上位トレイトの宣言一覧.extend(他.上位トレイトの宣言一覧);
        self.抽出できなかった行一覧.extend(他.抽出できなかった行一覧);
    }

    /// 成果の宣言の上で定義の式を評価して関係を導き、設計関係グラフと抽出の欠けへ組む。型の名前の定義の探索はソース群へ問う。
    /// 設計解釈マーカーの宣言の一覧は評価の前に組む。命令の組を通した変換用の素材にする規則が、組とコマンドの付いているマーカーを本体の条件に読むためである。
    /// ノードは、設計解釈マーカーの宣言の一覧の端点・宣言が立てるノード・導いた関係の端点の順に並べる。組み立てが見つけた同一性の衝突は、この値が運んで入口の表示まで届ける。
    pub fn 設計関係グラフと抽出の欠けを組む(self, ソース群: &抽出対象のソース群) -> 抽出した設計関係グラフと抽出の欠け {
        let 設計解釈マーカーの宣言の一覧 = 設計解釈マーカーの宣言の一覧::生成する(設計解釈マーカーの参照一覧(), self.マーカーの実装一覧, self.上位トレイトの宣言一覧);
        let 導出 = 定義の式::設計の関係とプリミティブな関係の定義().評価する(&self.プリミティブな宣言, &設計解釈マーカーの宣言の一覧, ソース群);
        let (端点の概念一覧, 設計関係一覧, プリミティブな関係一覧, 欠け一覧) = 導出.端点と関係と欠けへ分ける();
        let mut 概念一覧 = self.概念一覧;
        概念一覧.extend(self.プリミティブな宣言.宣言が立てる概念一覧());
        概念一覧.extend(端点の概念一覧);
        let mut 抽出できなかった行一覧 = self.抽出できなかった行一覧;
        抽出できなかった行一覧.extend(欠け一覧.into_iter().map(抽出できなかった行::導出の欠けから生成する));
        let (グラフ, 同一性の衝突一覧) = 設計関係グラフ::生成する(概念一覧, 設計関係一覧, プリミティブな関係一覧, 設計解釈マーカーの宣言の一覧).グラフと同一性の衝突一覧へ分ける();
        抽出した設計関係グラフと抽出の欠け::生成する(グラフ, self.プリミティブな宣言, 抽出できなかった行一覧, 同一性の衝突一覧)
    }
}
