//! 命令の組か組の中のコマンドの定義を、組を受け取る状態遷移の宣言やフィールドの行から見てたどれないとき、
//! 処理がコマンドを変換用の素材にするという問いがエッジの不在から反証済みにならず、未決定になることを固定する回帰試験。
//!
//! 命令の組を通した変換用の素材にする規則は、組とコマンドを名指したうえでその付いているマーカーを問う。名指せなかった型にはモジュールパスの空のノードが当たり、
//! そのノードは設計解釈マーカーの宣言の一覧を持たないため、本体が成り立たずに変換用の素材にするの関係ごと落ちる。組をたどれなかったとき、問いの両端は定義をたどれた型のノードであり、
//! どちらにも同じ名前の空のノードが無いため、構造の検証器の空のノードの止めが効かない。この欠けを欠落へ数えないと、エッジの不在から偽の反証が出る。

use super::super::抽出の試験の段取り::原文から設計関係グラフと抽出の欠けを組む;
use blitz_design_verification::設計関係の有無命題;
use blitz_design_verification::{原子命題, 命題, 命題の検証器, 未決定の理由, 検証結果, 構造の検証器, 欠落が弱める答え, 設計概念の識別用情報, 関数の引数と戻り値の役目, 項};

const 状態遷移のパス: &str = "crates/blitz_esca/src/歩行の状態遷移.rs";
const 操作のパス: &str = "crates/blitz_esca/src/操作.rs";
const 命令のパス: &str = "crates/blitz_esca/src/命令.rs";

const 状態の定義: &str = "pub struct 旅行者の現在地 {\n    東: f32,\n}\n\nimpl 旅行者の現在地 {}\n\n";
const 組の定義: &str = "pub struct 胴体の命令 {\n    水平: 水平移動の操作,\n}\n\nimpl M命令の組 for 胴体の命令 {}\n\n";
const 操作の原文: &str = "pub enum 水平移動の操作 {\n    止まる,\n}\n\nimpl Mコマンド for 水平移動の操作 {}\n";
const 状態遷移の宣言: &str = "const _: M状態遷移が受け取る命令で決まる状態遷移関数<旅行者の現在地, 胴体の命令> = M状態遷移が受け取る命令で決まる状態遷移関数::生成する(旅行者の現在地::命令で動かす);\n";

// 原文を抽出して欠落を写し、宣言が包んだ処理が水平移動の操作を変換用の素材にするかを構造の検証器へ問う。
fn 処理が水平移動の操作を変換用の素材にするかを問う(原文一覧: &[(&str, &str)]) -> 検証結果 {
    let 抽出したもの = 原文から設計関係グラフと抽出の欠けを組む(原文一覧);
    let 処理 = 設計概念の識別用情報::処理として生成する("blitz_esca::歩行の状態遷移", "命令で動かす").所有者を添える(vec!["旅行者の現在地".to_string()]);
    let 問い = 命題::原子から組む(原子命題::設計関係の有無命題(設計関係の有無命題::生成する(
        項::名指した概念(処理),
        関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す(),
        項::名指した概念(設計概念の識別用情報::型として生成する("blitz_esca::操作", "水平移動の操作")),
    )));
    構造の検証器::生成する(抽出したもの.グラフ(), 抽出したもの.設計関係の抽出漏れへ写す()).検証する(&問い)
}

fn 欠落による未決定か(結果: &検証結果) -> bool {
    matches!(結果, 検証結果::未決定(未決定の理由::設計関係の抽出漏れが在る(_)))
}

// 対照: 状態遷移の宣言のファイルがコマンドを取り込めば、組を通した変換用の素材にする関係が導かれて証明済みになる。
#[test]
fn コマンドを取り込めば組を通した変換用の素材にする関係が証明される() {
    let 状態遷移の原文 = format!("use crate::操作::水平移動の操作;\n\n{状態の定義}{組の定義}{状態遷移の宣言}");
    let 結果 = 処理が水平移動の操作を変換用の素材にするかを問う(&[(状態遷移のパス, &状態遷移の原文), (操作のパス, 操作の原文)]);
    assert!(結果.証明済みか(), "試験の段取りが組を通した変換用の素材にする関係を導いていない: {}", 結果.表記());
}

