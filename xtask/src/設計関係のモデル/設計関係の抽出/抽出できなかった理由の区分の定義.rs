//! 抽出できなかった理由の区分とは、抽出できなかった行が設計関係を失ったかどうかと、失ったならソースのどの事実を読めなかったかの区別のことである。
//! 受け取るのは抽出できなかった理由、返すのは区分である。
//!
//! 区分が要るのは、検証器が辺の不在を根拠にしてよいかが区分で決まるためである。識別子のモジュールパスだけが求まっていない行と、設計概念でないため明示して除外した行は、
//! 設計関係そのものは失われていない。設計関係そのものを抽出できなかった行だけが、グラフに在るはずの辺を欠く。
//! その行がソースのどの事実を読めなかったかも区分が持つ。抽出の欠落は、読めなかった事実を本体で読む規則の関係の答えだけを弱めるためである。
//! 区分を答えるメソッドを理由の側が持つのは、どの選択肢がどの区分かを知っているのが、その選択肢を作った抽出器の側だからである。
//! 定義の式の評価器が導けなかった行は、ここで答える事実でなく、欠けた規則の頭の関係を行が持つ(`抽出できなかった行::読めなかった箇所`)。
//! 評価器からだけ届く理由(規則の本体の途中で名指した型の定義をたどれなかった)は、ソースの事実を持たない4つ目の区分へ属する。この区分は落とした頭の関係を持ち、
//! 行がどこで読めなかったかを別に見なくても弱める答えが決まる。

use blitz_design_verification::{プリミティブな関係の種類, 落とした事実の種類, 頭の関係};

use super::保証範囲の外の構文の定義::保証範囲の外の構文;
use super::抽出できなかった行の定義::{抽出できなかった理由, 抽出できなかった行, 読めなかった箇所};

/// 抽出できなかった理由が属する区分。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 抽出できなかった理由の区分 {
    /// 識別子のモジュールパスだけが求まっていない。関係そのものは保存されており、節点のモジュールパスが空になっただけである。
    識別子のモジュールパスだけが求まっていない,
    /// 設計概念でないため明示して除外した。除外の条件を書き下せており、落ちた設計関係は無い。
    設計概念でないため明示して除外した,
    /// 本来あり得る設計関係そのものを抽出できなかった。グラフに在るはずの辺を欠く。持つのは、ソースの構文から読めなかった事実である。
    設計関係そのものを抽出できなかった(ソースで読めなかった事実),
    /// 定義の式の評価器が規則の本体を成り立たせられず、落とした頭の関係を持つ。ソースの構文からは生じない。
    定義の式の規則の本体で関係ごと落とした(頭の関係),
}

/// 設計関係そのものを抽出できなかった行が、ソースの構文から読めなかった事実。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ソースで読めなかった事実 {
    /// その種類の事実を1件読めなかった。
    事実(落とした事実の種類),
    /// 本番のモジュールの本体を読めず、そこに在るはずの事実をどれも読めなかった。
    モジュールの全部,
}

impl 抽出できなかった理由 {
    /// この理由が属する区分。
    ///
    /// `定義のモジュールパスを求められなかった` を識別子のモジュールパスだけが求まっていないとするのは、抽出器がその行から関係を組んだうえで
    /// 節点のモジュールパスを空にしているためである。辺はグラフへ入っており、触れた原子命題は
    /// `未決定の理由::型の定義のモジュールパスが求まっていない` が別に止める。
    /// 規則の本体の途中の変数の定義をたどれない欠けはこれに当たらない。空の節点のために頭の関係ごと落ち、辺がグラフへ入らないためである。
    ///
    /// `型引数である` と `関数の署名の型引数である` と `役割の型自身の宣言である` と `Graphiteの生成物の取り込みである` と `署名を読まずに外した関数である`
    /// (設計語彙のクレートの関数と標準ライブラリのトレイトの実装の関数)を
    /// 設計概念でないため明示して除外したとするのは、どれもその位置に落ちた設計関係が無く、外す条件も書き下せているためである。
    /// `関数の署名の型引数である` は、トレイトの境界(寿命と `?Sized` を除く)を型引数の `:` の後ろにも `where` 句にも持たない型引数の名前だけが当たる。
    /// 境界を持つ型引数は定義の式が境界のトレイトへ読み替えるため、この理由へ届かない。境界の無い型引数はどの設計概念も名指さない。
    ///
    /// 残る選択肢は、どれも主語か目的語を決められずに関係を1件も組めていないか、抽出器がその文字列を読めずに辺をグラフへ入れられない。
    /// 型定義の宣言と本体の行はフィールドの型の表記を、役割の使用箇所の行は関数の役割の宣言を、`impl Mエンティティ` の本体はエンティティの識別子の関連型を、
    /// `trait` の宣言は分類の事実(上位トレイトの宣言)を読めなかった。
    pub const fn 区分(&self) -> 抽出できなかった理由の区分 {
        use ソースで読めなかった事実::事実;
        match self {
            Self::定義のモジュールパスを求められなかった { .. } => 抽出できなかった理由の区分::識別子のモジュールパスだけが求まっていない,
            Self::規則の本体の途中で名指した型の定義をたどれなかった { 導けなかった関係, .. } => 抽出できなかった理由の区分::定義の式の規則の本体で関係ごと落とした(*導けなかった関係),
            Self::型引数である { .. } | Self::関数の署名の型引数である { .. } | Self::役割の型自身の宣言である { .. } | Self::Graphiteの生成物の取り込みである { .. } | Self::署名を読まずに外した関数である { .. } => {
                抽出できなかった理由の区分::設計概念でないため明示して除外した
            }
            Self::保証範囲の外の構文である { 構文 } => 抽出できなかった理由の区分::設計関係そのものを抽出できなかった(構文が読めなかった事実(構文)),
            Self::役割の型引数の数が合わない { .. }
            | Self::役割の値の右辺が役割の生成する呼び出しでない { .. }
            | Self::役割に包まれた関数の引数がパスでない { .. }
            | Self::役割に包まれた関数のパスの区分が2つでない { .. }
            | Self::役割に包まれた関数のパスが起点の予約語で始まる { .. }
            | Self::役割に包まれた関数の所有者の実装が同じファイルに無い { .. }
            | Self::役割に包まれた関数の定義が一意に決まらない { .. } => 抽出できなかった理由の区分::設計関係そのものを抽出できなかった(事実(落とした事実の種類::関数の役割の宣言)),
            Self::項目の位置でない関数である { .. } | Self::関数の見出しが行の頭に無い { .. } | Self::関数の見出しを読めない { .. } | Self::関数の署名の型の表記を読めない { .. } => {
                抽出できなかった理由の区分::設計関係そのものを抽出できなかった(事実(落とした事実の種類::関数の署名))
            }
            Self::エンティティの識別子の関連型が無い { .. } => 抽出できなかった理由の区分::設計関係そのものを抽出できなかった(事実(落とした事実の種類::エンティティの識別子の関連型)),
        }
    }
}

impl 抽出できなかった行 {
    /// 関数の署名を読めなかった行か。ソースの構文で関数の署名の事実を読めなかった行と、定義の式の関数の署名の規則の本体で読めなかった行が当たる。
    /// 関数の署名の計測が、この行を理由ごとに数える。
    /// 設計概念でないため明示して除外した行(境界の無い型引数など)は、読めなかった行に数えない。
    pub fn 関数の署名を読めなかった行か(&self) -> bool {
        if self.理由.区分() == 抽出できなかった理由の区分::設計概念でないため明示して除外した {
            return false;
        }
        match self.読めなかった箇所 {
            読めなかった箇所::定義の式の規則の本体 {
                導けなかった関係: 頭の関係::プリミティブな関係(種類),
            } => 種類 != プリミティブな関係の種類::保持する,
            読めなかった箇所::定義の式の規則の本体 {
                導けなかった関係: 頭の関係::設計関係(_)
            } => false,
            読めなかった箇所::ソースの構文 => self.理由.区分() == 抽出できなかった理由の区分::設計関係そのものを抽出できなかった(ソースで読めなかった事実::事実(落とした事実の種類::関数の署名)),
        }
    }
}

// 保証範囲の外の構文が、ソースのどの事実を読めなかったか。`型の表記を読めない` がソースの構文から来るのは役割の使用箇所の型引数だけである。
const fn 構文が読めなかった事実(構文: &保証範囲の外の構文) -> ソースで読めなかった事実 {
    use ソースで読めなかった事実::{モジュールの全部, 事実};
    match 構文 {
        保証範囲の外の構文::本番の条件付きコンパイルを判定できない | 保証範囲の外の構文::本番のモジュールを辿れない => モジュールの全部,
        保証範囲の外の構文::型定義の宣言が1行に収まっていない { .. }
        | 保証範囲の外の構文::型定義の型引数に入れ子の型引数がある { .. }
        | 保証範囲の外の構文::位置で並べた本体の型を区切れない { .. }
        | 保証範囲の外の構文::型定義の本体の行がフィールドの記述でない { .. } => 事実(落とした事実の種類::フィールドの型の表記),
        保証範囲の外の構文::型の表記を読めない(_) | 保証範囲の外の構文::役割の型引数の不等号が同じ行で閉じない { .. } | 保証範囲の外の構文::同じ文に役割の使用が複数ある { .. } => {
            事実(落とした事実の種類::関数の役割の宣言)
        }
        保証範囲の外の構文::トレイトの見出しを読み切れない { .. } => 事実(落とした事実の種類::分類の事実),
    }
}
