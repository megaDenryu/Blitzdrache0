//! 抽出対象のソース群が、トレイトの実装の見出しに書いたトレイトの表記が標準ライブラリ(`std`・`core`・`alloc`)のトレイトを指すかを答える工程。
//! 受け取るのはトレイトの表記と、それを書いた行、返すのは標準ライブラリのトレイトを指すかである。関数の署名の抽出が、標準ライブラリのトレイトの実装の関数を明示して外すために問う。
//! 見分け方は定義の式が型の表記を読むのと同じ定義の探索の口(`型の名前の定義の探索`)であり、修飾の付いた表記(`std::ops::Add<Self>`・`fmt::Display`)も、
//! `use` で取り込んだ名前とプレリュードのトレイト(`Clone`・`Iterator`)も同じ答えになる。型引数(`Add<Self>` の `<Self>`)は落として名前だけを問う。

use super::抽出対象のソース群;
use blitz_design_verification::{Rustの項目の種類, 事実の出どころ, 修飾された名前の定義を探した結果, 修飾の無い名前の定義を探した結果, 型の名前の定義の探索};

impl 抽出対象のソース群 {
    /// トレイトの表記が、書いた行から見て標準ライブラリのトレイトを指すか。
    pub fn トレイトの表記が標準ライブラリのトレイトを指すか(&self, トレイトの表記: &str, 参照元: &事実の出どころ) -> bool {
        let パス = トレイトの表記.split('<').next().unwrap_or_default().trim();
        match パス.rsplit_once("::") {
            Some((修飾, 名前)) => self.修飾された名前の定義を探す(修飾.trim(), 名前.trim(), Rustの項目の種類::トレイト, 参照元) == 修飾された名前の定義を探した結果::標準ライブラリの項目である,
            None => self.修飾の無い名前の定義を探す(パス, Rustの項目の種類::トレイト, 参照元) == 修飾の無い名前の定義を探した結果::標準ライブラリの項目である,
        }
    }
}
