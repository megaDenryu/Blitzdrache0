//! 抽出対象のソース群が、定義の式の評価器へ型の名前の定義の探索の口を実装する(トレイト実装の分離)。
//! 答えは構文解析器の型の定義の探索に問い、`型の識別子を求める` と同じ探し方で求める。

use super::抽出対象のソース群;
use crate::conform::設計オントロジーの規約検査::type_definition::{型の在り処の問い, 定義ブロックの結果};
use blitz_design_verification::{型の名前の定義の探索, 宣言の出どころ};

impl 型の名前の定義の探索 for 抽出対象のソース群 {
    /// 定義の式が型の表記の芯の名前を採ったときに問う口。表記を書いた行から見た定義の在り処を答える。
    /// 定義は座標系を落とした名前で探す(定義の式が落としてから問う)。`blitz_math` のフレーム型はたどれず、無しを答える。
    fn 型の定義のモジュールパスを探す(&self, 型名: &str, 参照元: &宣言の出どころ) -> Option<String> {
        let 問い = 型の在り処の問い {
            型名,
            参照元のパス: &参照元.パス,
            参照元の行番号: 参照元.行番号,
        };
        match self.構文検査.探索の材料().定義の在り処を探す(&問い) {
            定義ブロックの結果::見つかった { パス, .. } => Some(self.ファイルのモジュールパス(&パス)),
            定義ブロックの結果::見つからない | 定義ブロックの結果::複数ある | 定義ブロックの結果::別名のため取り込み元を求められない => None,
        }
    }
}
