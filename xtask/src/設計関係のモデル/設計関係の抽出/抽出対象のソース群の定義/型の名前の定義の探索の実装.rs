//! 抽出対象のソース群が、定義の式の評価器へ型の名前の定義の探索の口を実装する(トレイト実装の分離)。
//! 修飾の無い名前は構文解析器の型の定義の探索で答え、定義が見つからなければ、標準ライブラリから取り込んだ名前か、一括取り込み(`use a::*;`)が持ち込んだ名前か、
//! プレリュードのトレイトかを問う(見える定義の無い名前の出どころ)。
//! 修飾の付いた名前は型の定義の探索の修飾したパスの定義の探索で答える。

use super::抽出対象のソース群;
use crate::conform::設計オントロジーの規約検査::type_definition::{
    修飾したパスを探した結果, 型の在り処の問い, 定義ブロックの結果, 探す定義の宣言の種類, 見える定義の無い名前の出どころ
};
use blitz_design_verification::{Rustの項目の種類, 事実の出どころ, 修飾された名前の定義を探した結果, 修飾の無い名前の定義を探した結果, 型の名前の定義の探索};

impl 型の名前の定義の探索 for 抽出対象のソース群 {
    /// 定義の式が型の表記の芯の名前を採ったときに問う口。表記を書いた行から見た定義の在り処を、`型の識別子を求める` と同じ探し方で答える。
    /// 定義は座標系を落とした名前で探す(定義の式が落としてから問う)。`blitz_math` のフレーム型はたどれず、無しを答える。
    /// トレイトは `trait` の宣言を型と同じ探し方で探す。定義の式は型の表記から処理を名指さないため、処理の問いは不変条件の破れとして止める。
    fn 修飾の無い名前の定義を探す(&self, 名前: &str, 種類: Rustの項目の種類, 参照元: &事実の出どころ) -> 修飾の無い名前の定義を探した結果 {
        let (問い, 宣言, 材料) = (在り処の問い(名前, 参照元), 探す宣言(名前, 種類), self.構文検査.探索の材料());
        match 材料.定義の在り処を探す(&問い, 宣言) {
            定義ブロックの結果::見つかった { パス, .. } => 修飾の無い名前の定義を探した結果::定義がある {
                モジュールパス: self.ファイルのモジュールパス(&パス),
            },
            定義ブロックの結果::見つからない => match 材料.見える定義の無い名前の出どころを求める(&問い, 宣言) {
                見える定義の無い名前の出どころ::標準ライブラリの項目である => 修飾の無い名前の定義を探した結果::標準ライブラリの項目である,
                見える定義の無い名前の出どころ::一括取り込み元に定義がある { パス } => 修飾の無い名前の定義を探した結果::定義がある {
                    モジュールパス: self.ファイルのモジュールパス(&パス),
                },
                見える定義の無い名前の出どころ::たどれない => 修飾の無い名前の定義を探した結果::定義をたどれない,
            },
            定義ブロックの結果::複数ある | 定義ブロックの結果::別名のため取り込み元を求められない => 修飾の無い名前の定義を探した結果::定義をたどれない,
        }
    }

    /// 修飾を `use` の取り込みから求めたモジュールで、名前の定義を型かトレイトの探し方でたどる。
    fn 修飾された名前の定義を探す(&self, 修飾: &str, 名前: &str, 種類: Rustの項目の種類, 参照元: &事実の出どころ) -> 修飾された名前の定義を探した結果 {
        match self.構文検査.探索の材料().修飾したパスの定義を探す(&在り処の問い(名前, 参照元), 修飾, 探す宣言(名前, 種類)) {
            修飾したパスを探した結果::標準ライブラリの項目である => 修飾された名前の定義を探した結果::標準ライブラリの項目である,
            修飾したパスを探した結果::見つかった { パス } => 修飾された名前の定義を探した結果::定義がある {
                モジュールパス: self.ファイルのモジュールパス(&パス),
            },
            修飾したパスを探した結果::見つからない => 修飾された名前の定義を探した結果::定義をたどれない,
            修飾したパスを探した結果::修飾の頭が型である => 修飾された名前の定義を探した結果::型の関連項目である,
        }
    }
}

// 定義の式の問いを、型の定義の探索の問いへ写す。
fn 在り処の問い<'a>(名前: &'a str, 参照元: &'a 事実の出どころ) -> 型の在り処の問い<'a> {
    型の在り処の問い {
        型名: 名前,
        参照元のパス: &参照元.パス,
        参照元の行番号: 参照元.行番号,
    }
}

// 定義の式が問う種類を、探す定義の宣言の種類へ写す。定義の式は型の表記から処理を名指さないため、処理の問いは不変条件の破れとして止める。
fn 探す宣言(名前: &str, 種類: Rustの項目の種類) -> 探す定義の宣言の種類 {
    match 種類 {
        Rustの項目の種類::型 => 探す定義の宣言の種類::型,
        Rustの項目の種類::トレイト => 探す定義の宣言の種類::トレイト,
        Rustの項目の種類::処理 => panic!("定義の式が型の表記から処理 {名前} の定義を問うた: 定義の式は型の表記から型かトレイトだけを名指すという不変条件が破れた"),
    }
}
