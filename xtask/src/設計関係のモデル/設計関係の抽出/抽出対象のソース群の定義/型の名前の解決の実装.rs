//! 抽出対象のソース群が、定義の式の評価器へ型の名前の解決の口を実装する(トレイト実装の分離)。
//! 修飾の無い名前は構文解析器の型の定義の探索で、修飾の付いた名前は型の定義の探索の修飾したパスの解決で答える。

use super::抽出対象のソース群;
use crate::conform::設計オントロジーの規約検査::type_definition::{修飾したパスを探した結果, 型の在り処の問い, 定義ブロックの結果, 探す定義の宣言};
use blitz_design_verification::{Rustの項目の種類, 事実の出どころ, 修飾された名前の解決, 型の名前の解決};

impl 型の名前の解決 for 抽出対象のソース群 {
    /// 定義の式が型の表記の芯の名前を採ったときに問う口。表記を書いた行から見た定義の在り処を、`型の識別子を求める` と同じ探し方で答える。
    /// 定義は座標系を落とした名前で探す(定義の式が落としてから問う)。`blitz_math` のフレーム型はたどれず、無しを答える。
    /// トレイトは `trait` の宣言を型と同じ探し方で探す。定義の式は型の表記から処理を名指さないため、処理の問いは不変条件の破れとして止める。
    fn 定義のモジュールパスを求める(&self, 名前: &str, 種類: Rustの項目の種類, 参照元: &事実の出どころ) -> Option<String> {
        match self.構文検査.探索の材料().定義の在り処を探す(&在り処の問い(名前, 参照元), 探す宣言(名前, 種類)) {
            定義ブロックの結果::見つかった { パス, .. } => Some(self.ファイルのモジュールパス(&パス)),
            _ => None,
        }
    }

    /// 修飾を `use` の取り込みから解決したモジュールで、名前の定義を型かトレイトの探し方でたどる。
    fn 修飾された名前を解決する(&self, 修飾: &str, 名前: &str, 種類: Rustの項目の種類, 参照元: &事実の出どころ) -> 修飾された名前の解決 {
        match self.構文検査.探索の材料().修飾したパスの定義を探す(&在り処の問い(名前, 参照元), 修飾, 探す宣言(名前, 種類)) {
            修飾したパスを探した結果::標準ライブラリの項目である => 修飾された名前の解決::標準ライブラリの項目である,
            修飾したパスを探した結果::見つかった { パス } => 修飾された名前の解決::定義がある {
                モジュールパス: self.ファイルのモジュールパス(&パス),
            },
            修飾したパスを探した結果::見つからない => 修飾された名前の解決::定義をたどれない,
            修飾したパスを探した結果::修飾の頭が型である => 修飾された名前の解決::型の関連項目である,
        }
    }
}

// 定義の式の問いを、型の定義の探索の問いへ写す。
fn 在り処の問い<'a>(名前: &'a str, 参照元: &'a 事実の出どころ) -> 型の在り処の問い<'a> {
    型の在り処の問い {
        型名: 名前,
        参照元のパス: &参照元.パス,
        参照元の行番号: 参照元.行番号,
    }
}

// 定義の式が問う種類を、探す定義の宣言へ写す。定義の式は型の表記から処理を名指さないため、処理の問いは不変条件の破れとして止める。
fn 探す宣言(名前: &str, 種類: Rustの項目の種類) -> 探す定義の宣言 {
    match 種類 {
        Rustの項目の種類::型 => 探す定義の宣言::型,
        Rustの項目の種類::トレイト => 探す定義の宣言::トレイト,
        Rustの項目の種類::処理 => panic!("定義の式が型の表記から処理 {名前} の定義を問うた: 定義の式は型の表記から型かトレイトだけを名指すという不変条件が破れた"),
    }
}
