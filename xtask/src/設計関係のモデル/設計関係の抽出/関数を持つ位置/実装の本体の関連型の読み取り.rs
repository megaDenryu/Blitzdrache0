//! 実装の本体の関連型の読み取り。受け取るのはコードだけの行の一覧と `impl` の見出しの書き出しの行、返すのはその実装の本体の直下で宣言した関連型の並びである。
//! 依存を持たない純粋な関数だけを置く。関数を囲む本体が、本体の関数の型の表記に書いた `Self::関連型` を宣言の右辺へ置き換えるために読む。
//!
//! 関連型の宣言は関数より後ろに書いてもよいため、見出しを読んだ時点で本体の終わりまで先に読む。読むのは、本体を開く `{` の行より後ろで、
//! 行の頭が本体の直下(実装の本体の波括弧だけが開いている位置)にある `type 名前 = 右辺;` の行である。宣言は `;` まで複数の行にわたってよい。
//! 本体を開く `{` と同じ行に書いた宣言(1行に書いた本体)は読まない。その `Self::関連型` は置き換わらず、定義の式が読めない表記として欠けに数える。

use super::関数を囲む本体の定義::関連型の宣言;
use crate::conform::設計オントロジーの規約検査::declaration_brackets::{最上位で開いた括弧, 見出しの括弧の深さ};
use crate::conform::設計オントロジーの規約検査::line_matching::{先頭の型引数を分ける, 先頭の識別子};
use crate::conform::設計オントロジーの規約検査::属性と可視性の前置き::属性と可視性を読み飛ばす;

/// `impl` の見出しの書き出しの行から本体の終わりまでを読み、本体の直下で宣言した関連型を並べる。見出しの型引数の定数式の波括弧は本体の波括弧と区別する。
pub(super) fn 実装の本体の関連型を読む(行一覧: &[String], 見出しの行: usize) -> Vec<関連型の宣言> {
    let mut 括弧 = 見出しの括弧の深さ::default();
    let mut 本体の深さ: Option<usize> = None;
    let mut 一覧 = Vec::new();
    for (添字, 行) in 行一覧.iter().enumerate().skip(見出しの行) {
        if 本体の深さ == Some(1) {
            一覧.extend(関連型の宣言を読む(行一覧, 添字));
        }
        for 文字 in 行.chars() {
            本体の深さ = match (本体の深さ, 文字) {
                (None, _) => (括弧.一文字読む(文字) == 最上位で開いた括弧::本体の波括弧).then_some(1),
                (Some(深さ), '{') => Some(深さ + 1),
                (Some(深さ), '}') => Some(深さ.saturating_sub(1)),
                (Some(深さ), _) => Some(深さ),
            };
            if 本体の深さ == Some(0) {
                return 一覧;
            }
        }
    }
    一覧
}

// その行が本体の直下の `type 名前 = 右辺;` の書き出しなら、`;` までを繋いで読んだ関連型の宣言。
fn 関連型の宣言を読む(行一覧: &[String], 添字: usize) -> Option<関連型の宣言> {
    let 後ろ = 属性と可視性を読み飛ばす(行一覧[添字].trim()).strip_prefix("type ")?.trim_start();
    let mut 宣言 = 後ろ.to_string();
    for 続き in 行一覧.iter().skip(添字 + 1) {
        if 宣言.contains(';') {
            break;
        }
        宣言.push(' ');
        宣言.push_str(続き.trim());
    }
    let 名前 = 先頭の識別子(&宣言);
    let (_, 型引数より後ろ) = 先頭の型引数を分ける(宣言[名前.len()..].trim_start());
    let 右辺 = 型引数より後ろ.trim_start().strip_prefix('=')?.split(';').next()?.trim();
    (!名前.is_empty() && !右辺.is_empty()).then(|| 関連型の宣言 { 名前, 右辺の表記: 右辺.to_string() })
}
