//! 次に開く波括弧で開く本体(実装かトレイトの本体なら関数を書いた場所の材料)である。依存を持たない純粋な関数だけを置く。
//! 走査の状態を持つ `関数を持つ位置の走査` から分けるのは、見出し1つから本体の区分を読む規則が、開いている波括弧の並びに触れないためである。

