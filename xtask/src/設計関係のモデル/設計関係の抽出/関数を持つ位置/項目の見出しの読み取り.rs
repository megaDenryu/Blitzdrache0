/// 行が `impl`・`trait`・`mod 名 {` の見出しなら、その見出しが次に開く本体。位置のモジュールは、トレイトの節点の識別子に使う。
pub(super) fn 見出しから次に開く本体を読む(行一覧: &[String], 添字: usize, 位置のモジュール: &モジュールパス) -> Option<次に開く本体> {
    if let Some(見出し) = implの見出しを読む(行一覧, 添字) {
        let 構文 = 見出し.構文を読む()?;
        let 型引数名一覧 = 構文.型引数の名前一覧().to_vec();
        let (型引数の並び, where句) = 構文.型引数の並びとwhere句();
        let 型引数の境界一覧 = 型引数の境界を読む(型引数の並び, where句);
        // トレイトの実装の関数は、同じ型の固有の実装の同じ名前の関数と別の処理であり、同じトレイトを型引数だけ変えて実装した関数どうしも別の処理である。
        // そのため所有者の並びへ、対象の型の名前に続けてトレイトを書いた位置の表記(型引数を含む)を足す。
        let 所有者の名前一覧 = [構文.対象.名前().to_string()].into_iter().chain(構文.トレイトの表記().map(str::to_string)).collect();
        let 本体 = 開いた波括弧::実装かトレイトの本体(関数を囲む本体 {
            所有者の名前一覧,
            所有者: 関数の所有者::型(型の表記::生成する(構文.対象.表記(), 型引数名一覧.clone())),
            型引数名一覧,
            型引数の境界一覧,
            実装したトレイトの表記: 構文.トレイトの表記().map(str::to_string),
            関連型一覧: 実装の本体の関連型を読む(行一覧, 添字),
            見出しの行の添字: Some(添字),
        });
        return Some(次に開く本体 {
            読み飛ばす波括弧の数: 見出し.表記.matches('{').count().saturating_sub(1),
            本体,
        });
    }
    let 頭 = 属性と可視性を読み飛ばす(行一覧[添字].trim());
    if let Some(後ろ) = 頭.strip_prefix("mod ") {
        let 本体 = モジュールの本体を読む(後ろ.trim_start())?;
        return Some(次に開く本体 { 読み飛ばす波括弧の数: 0, 本体 });
    }
    let トレイトの見出しの構文の読み取り::読めた(構文) = トレイトの見出しの構文を読む(行一覧, 添字) else {
        return None;
    };
    Some(次に開く本体 {
        読み飛ばす波括弧の数: 構文.本体より前に開く波括弧の数,
        本体: トレイトの本体を組む(構文, 位置のモジュール, 添字),
    })
}

// トレイトの見出しの構文から、トレイトの本体を組む。トレイトの `Self` は実装する型の総称であり名指す型が無いため、型引数の名前に数え、
// そのトレイト自身と上位トレイトを境界に持つ型引数として扱う(`Self::関連型` を定義の式がそのトレイトとして読む)。上位トレイトは `trait A: B` と
// `trait A where Self: B` のどちらで書いても同じ一覧になる(`トレイトの宣言の行` の読み方)。トレイトの型引数の境界は、見出しの型引数と `where` 句から読む。
fn トレイトの本体を組む(構文: トレイトの見出しの構文, 位置のモジュール: &モジュールパス, 見出しの行の添字: usize) -> 開いた波括弧 {
    let mut 型引数名一覧 = 型の引数の名前一覧(&構文.型引数の並び);
    型引数名一覧.push("Self".to_string());
    let 識別子 = 設計概念の識別子::Rustの項目として生成する(位置のモジュール.表記(), &構文.名前);
    let 自分の型の境界 = 型引数の境界::生成する("Self", std::iter::once(構文.名前.clone()).chain(構文.上位トレイト一覧).collect());
    let mut 型引数の境界一覧 = 型引数の境界を読む(&構文.型引数の並び, &構文.where句);
    型引数の境界一覧.push(自分の型の境界);
    開いた波括弧::実装かトレイトの本体(関数を囲む本体 {
        所有者の名前一覧: vec![構文.名前],
        所有者: 関数の所有者::トレイト(設計概念への参照::Rustの項目として生成する(識別子, Rustの項目の種類::トレイト)),
        型引数名一覧,
        型引数の境界一覧,
        実装したトレイトの表記: None,
        関連型一覧: Vec::new(),
        見出しの行の添字: Some(見出しの行の添字),
    })
}

// `mod 名 {` の `mod` より後ろから、そのモジュールの本体。本体を別のファイルに持つ `mod 名;` は無しである。
fn モジュールの本体を読む(後ろ: &str) -> Option<開いた波括弧> {
    let 名前 = 先頭の識別子(後ろ);
    (!名前.is_empty() && 後ろ[名前.len()..].trim_start().starts_with('{')).then_some(開いた波括弧::モジュールの本体(名前))
}

