//! 項目の見出しの読み取り。受け取るのはコードだけの行の一覧と見出しの行と位置のモジュール、返すのは、その行が `impl`・`trait`・`mod 名 {` の見出しなら、
//! 次に開く波括弧で開く本体(実装かトレイトの本体なら関数を書いた場所の材料、見出しを読めない実装かトレイトならその本体)である。依存を持たない純粋な関数だけを置く。
//! 走査の状態を持つ `関数を持つ位置の走査` から分けるのは、見出し1つから本体の区分を読む規則が、開いている波括弧の並びに触れないためである。

use super::super::トレイトの宣言の行::{トレイトの見出しの構文, トレイトの見出しの構文の読み取り, トレイトの見出しの構文を読む};
use super::super::関数の見出しの読み取り::型引数の境界の読み取り::型引数の境界を読む;
use super::実装の本体の関連型の読み取り::実装の本体の関連型を読む;
