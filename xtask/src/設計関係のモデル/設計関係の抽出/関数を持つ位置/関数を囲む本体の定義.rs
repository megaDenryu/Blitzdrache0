//! 関数を囲む本体とは、項目の位置の関数を囲む実装かトレイトの本体(モジュールの直下の自由関数なら無い所有者)について、関数の署名を組むのに要る材料をまとめたものである。
//! 所有者と処理の識別子へ添える所有者の名前の並び、そこで有効な型引数の名前と境界、トレイトの実装ならそのトレイトの表記と本体で宣言した関連型を持つ。
//!
//! 本体の型の表記の書き換え(`Self` と `Self::関連型` を実装の中で名指す型へ置き換えること)をこの型のメソッドにするのは、置き換えに要る材料(対象の型の表記と関連型の宣言)を
//! この型だけが持つためである。`Self::関連型` を先に関連型の宣言の右辺へ置き換え、残る `Self` を対象の型の表記へ置き換える。
//! 先に `Self` を置き換えると `型::関連型` になり、定義の式が型の関連項目として読めない表記に数えるためである。
//! 実装の本体に宣言の無い関連型(上位トレイトの関連型や既定の関連型)は置き換えず、定義の式が読めない表記として欠けに数える(抽出器の保証範囲の外である)。

use crate::conform::設計オントロジーの規約検査::identifier_boundary::識別子として現れる位置一覧;
use crate::conform::設計オントロジーの規約検査::line_matching::先頭の識別子;
use blitz_design_verification::{型引数の境界, 関数の所有者};

/// 実装の本体で宣言した関連型1つ(`type Item = 地点;` の `Item` と `地点`)。
#[derive(Clone)]
pub struct 関連型の宣言 {
    pub 名前: String,
    pub 右辺の表記: String,
}

#[derive(Clone)]
pub struct 関数を囲む本体 {
    pub 所有者の名前一覧: Vec<String>, // 処理の識別子の所有者の並び。自由関数では空、トレイトの実装では対象の型の名前とトレイトの表記の2つである
    pub 所有者: 関数の所有者,
    pub 型引数名一覧: Vec<String>,
    pub 型引数の境界一覧: Vec<型引数の境界>,    // 実装かトレイトの見出しの型引数と `where` 句の境界。トレイトの本体では `Self` の境界(そのトレイト)も持つ
    pub 実装したトレイトの表記: Option<String>, // トレイトの実装の本体なら、トレイトを書いた位置の表記(`Clone`・`std::ops::Add<Self>`)
    pub 関連型一覧: Vec<関連型の宣言>,          // 実装の本体の直下で宣言した関連型
}

impl 関数を囲む本体 {
    /// モジュールの直下の自由関数を囲む本体。所有者も型引数も無い。
    pub fn 自由関数の本体() -> Self {
        Self {
            所有者の名前一覧: Vec::new(),
            所有者: 関数の所有者::自由関数,
            型引数名一覧: Vec::new(),
            型引数の境界一覧: Vec::new(),
            実装したトレイトの表記: None,
            関連型一覧: Vec::new(),
        }
    }

    /// `impl` の本体なら、書かれた文字列の中の `Self::関連型` を関連型の宣言の右辺へ、残る識別子の `Self` を実装の対象の型の表記へ置き換える。それ以外は書かれた文字列のままである。
    pub fn 自分の型の予約語を実装の中の型へ置き換える(&self, 書かれた文字列: &str) -> String {
        let 関数の所有者::型(対象) = &self.所有者 else {
            return 書かれた文字列.to_string();
        };
        let mut 置き換えた = self.関連型を右辺へ置き換える(書かれた文字列);
        let 位置一覧 = 識別子として現れる位置一覧(&置き換えた, "Self");
        for 位置 in 位置一覧.into_iter().rev() {
            置き換えた.replace_range(位置..位置 + "Self".len(), 対象.書かれた文字列());
        }
        置き換えた
    }

    // 書かれた文字列の中の `Self::名前` のうち、名前が本体で宣言した関連型のものを、その右辺の表記へ置き換える。
    fn 関連型を右辺へ置き換える(&self, 書かれた文字列: &str) -> String {
        let mut 置き換えた = 書かれた文字列.to_string();
        for 位置 in 識別子として現れる位置一覧(書かれた文字列, "Self").into_iter().rev() {
            let Some(後ろ) = 書かれた文字列[位置 + "Self".len()..].strip_prefix("::") else {
                continue;
            };
            let 名前 = 先頭の識別子(後ろ);
            if let Some(宣言) = self.関連型一覧.iter().find(|宣言| 宣言.名前 == 名前) {
                置き換えた.replace_range(位置..位置 + "Self::".len() + 名前.len(), &宣言.右辺の表記);
            }
        }
        置き換えた
    }
}
