//! rustfmt が長い戻り値の型を `-> Result<` の次の行から `impl Iterator<Item = 地点> + 'a,` と折ったとき、行の頭が `impl` のその行を、
//! 関数を持つ位置の走査が実装の見出しと取り違えないことを固定する回帰試験。取り違えると、その行が次に開く波括弧を見出しを読めない実装の本体として予約する。

use super::super::super::抽出の試験の段取り::{原文から設計関係グラフと抽出の欠けを組む, 関係の表記一覧};

const 試験のパス: &str = "crates/blitz_game/src/試験.rs";

// 反証: 折った戻り値の型の行を実装の見出しと取り違えると、関数の本体を見出しを読めない実装の本体として開き、その中の局所の `impl 局所 {` を
// 項目の位置の実装と読んで、局所の関数を `局所` の関連関数として持つ関係にする。
#[test]
fn 本体のある関数の折った戻り値の型の行は関数の本体を実装の本体として開かない() {
    let 原文 = "pub struct 地点;\n\npub fn 並べる<'a>(値: &'a 地点) -> Result<\n    impl Iterator<Item = 地点> + 'a,\n    地点,\n> {\n    struct 局所;\n    impl 局所 {\n        fn 局所の関数(&self) {}\n    }\n    Err(地点)\n}\n";
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[(試験のパス, 原文)]);
    let 表記一覧 = 関係の表記一覧(&結果);
    assert!(表記一覧.contains(&"blitz_game::試験::並べる 引数に取る blitz_game::試験::地点".to_string()), "{表記一覧:?}");
    assert!(!表記一覧.iter().any(|表記| 表記.contains("局所の関数")), "{表記一覧:?}");
    let 呼び名一覧: Vec<&str> = 結果.抽出できなかった行一覧.iter().map(|行| 行.理由.種別の呼び名()).collect();
    assert!(呼び名一覧.contains(&"項目の位置でない関数である"), "{呼び名一覧:?}");
    assert!(!呼び名一覧.contains(&"見出しを読めない実装の本体の関数である"), "{呼び名一覧:?}");
}

// 反証: トレイトの本体の `>;` で終わる宣言の折った戻り値の型の行を実装の見出しと取り違えると、`;` で閉じたため予約が消えずに残り、
// 後ろの `impl 並べ役 {` の見出しを読まずにその本体を見出しを読めない実装の本体として開き、`使う` の署名を欠落にする。
#[test]
fn トレイトの本体の宣言の折った戻り値の型の行は後ろの実装の見出しの読み取りを妨げない() {
    let 原文 = "pub struct 地点;\n\npub trait 並べ手 {\n    fn 並べる<'a>(&'a self) -> Result<\n        impl Iterator<Item = 地点> + 'a,\n        地点,\n    >;\n}\n\npub struct 並べ役;\n\nimpl 並べ役 {\n    pub fn 使う(&self, 値: &地点) {}\n}\n";
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[(試験のパス, 原文)]);
    let 表記一覧 = 関係の表記一覧(&結果);
    assert!(表記一覧.contains(&"blitz_game::試験::並べ役::使う 引数に取る blitz_game::試験::地点".to_string()), "{表記一覧:?}");
    let 呼び名一覧: Vec<&str> = 結果.抽出できなかった行一覧.iter().map(|行| 行.理由.種別の呼び名()).collect();
    assert!(!呼び名一覧.contains(&"見出しを読めない実装の本体の関数である"), "{呼び名一覧:?}");
}
