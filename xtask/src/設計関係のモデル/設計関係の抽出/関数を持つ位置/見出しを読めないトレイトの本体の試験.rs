//! 見出しを読めないトレイトの本体に書いた関数を、抽出器が項目の位置でない関数と取り違えず、見出しを読めないトレイトの本体の関数として数え、
//! 関数の署名の欠落として残すことを固定する回帰試験。

use super::super::抽出の試験の段取り::{原文から設計関係グラフと抽出の欠けを組む, 抽出できなかった理由の説明一覧};
use super::署名を読めない関数の位置;
use super::関数を持つ位置の走査;
use crate::conform::設計オントロジーの規約検査::module_path::モジュールパス;

const 見出しを読めないトレイトの原文: &str = "pub trait 読めない<T: 甲<U> {\n    fn 使う(&self) -> u8;\n}\n";

// 反証: 読めないトレイトの見出しを見出しでないと扱うと、次に開く波括弧をその他の本体として開き、中の関数を項目の位置でない関数と報告する。
#[test]
fn 見出しを読めないトレイトの本体の関数は見出しを読めないトレイトの本体の位置と答える() {
    let 行一覧: Vec<String> = 見出しを読めないトレイトの原文.lines().map(str::to_string).collect();
    let mut 走査 = 関数を持つ位置の走査::生成する(モジュールパス::区切り一覧から組む(&["blitz_game", "試験"]));
    走査.行を読む(&行一覧, 0);
    let 期待 = 署名を読めない関数の位置::見出しを読めないトレイトの本体 { トレイト名: "読めない".to_string() };
    assert_eq!(走査.いまの関数を書いた場所().err(), Some(期待));
}

#[test]
fn 見出しを読めないトレイトの本体の関数は関数の署名の欠落として数える() {
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[("crates/blitz_game/src/試験.rs", 見出しを読めないトレイトの原文)]);
    let 呼び名一覧: Vec<&str> = 結果.抽出できなかった行一覧.iter().map(|行| 行.理由.種別の呼び名()).collect();
    assert!(呼び名一覧.contains(&"見出しを読めないトレイトの本体の関数である"), "{呼び名一覧:?}");
    assert!(!呼び名一覧.contains(&"項目の位置でない関数である"), "{呼び名一覧:?}");
    assert!(抽出できなかった理由の説明一覧(&結果).iter().any(|説明| 説明.contains("`使う` は見出しを読めないトレイト `読めない`")));
    assert!(結果.関係を落とした抽出の欠落へ写す().合計の件数() > 0);
}
