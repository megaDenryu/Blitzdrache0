//! 抽出できなかった理由を人が読む文にする工程。受け取るのは理由、返すのは同じ種別をまとめる見出しの呼び名と、運ぶ値を含めた1行の説明である。
//!
//! 理由の型の定義(親のモジュール)と分けるのは、報告の文面を直す変更と、理由の選択肢を足して区分を決める変更が別の理由で起きるためである。

use super::抽出できなかった理由;

impl 抽出できなかった理由 {
    /// 選択肢の種別の呼び名。運ぶ値(型名・役割名)を含めないのは、この呼び名が同じ種別をまとめた件数の見出しになるためである。
    pub const fn 種別の呼び名(&self) -> &'static str {
        match self {
            Self::型引数である { .. } => "定義の宣言が導入した型引数である",
            Self::定義のモジュールパスを求められなかった { .. } => "型の定義をたどれずモジュールパスを空にした",
            Self::規則の本体の途中で名指した型の定義をたどれなかった { .. } => "規則の本体の途中で名指した型の定義をたどれず頭の関係ごと落とした",
            Self::役割の型引数の数が合わない { .. } => "役割の型引数の数が合わない",
            Self::役割の値の右辺が役割の生成する呼び出しでない { .. } => "役割の値の右辺が役割の生成する呼び出しでない",
            Self::役割に包まれた関数の引数がパスでない { .. } => "役割に包まれた関数の引数がパスでない",
            Self::役割に包まれた関数のパスの区分が2つでない { .. } => "役割に包まれた関数のパスの区分が2つでない",
            Self::役割に包まれた関数のパスが起点の予約語で始まる { .. } => "役割に包まれた関数のパスが起点の予約語で始まる",
            Self::役割に包まれた関数の所有者の実装が同じファイルに無い { .. } => "役割に包まれた関数の所有者の実装が同じファイルに無い",
            Self::エンティティの識別子の関連型が無い { .. } => "エンティティの識別子の関連型が無い",
            Self::役割の型自身の宣言である { .. } => "関数の役割の型自身の宣言である",
            Self::保証範囲の外の構文である { 構文 } => 構文.種別の呼び名(),
            Self::Graphiteの生成物の取り込みである { .. } => "Graphiteの生成物の取り込みである",
        }
    }

    /// 人が読む説明。
    pub fn 説明(&self) -> String {
        match self {
            Self::型引数である { 型引数名 } => format!("`{型引数名}` は定義の宣言が導入した型引数であり設計概念ではない"),
            Self::定義のモジュールパスを求められなかった { 型名 } => format!("`{型名}` の定義をたどれずモジュールパスを空にした"),
            Self::規則の本体の途中で名指した型の定義をたどれなかった { 型名, .. } => {
                format!("`{型名}` は定義の式の規則の本体の途中で名指した型であり、定義をたどれず分類を問えないため、その規則の関係を導けなかった")
            }
            Self::役割の型引数の数が合わない { 役割名, 取る数, 読めた数 } => format!("`{役割名}` は型引数を{取る数}個取るが{読めた数}個しか読めなかった"),
            Self::役割の値の右辺が役割の生成する呼び出しでない { 役割名 } => format!("`{役割名}` の値の右辺が `{役割名}::生成する(...)` の形でなく主語を決められない"),
            Self::役割に包まれた関数の引数がパスでない { 役割名 } => format!("`{役割名}::生成する` へ渡した引数がRustのパスとして読めない"),
            Self::役割に包まれた関数のパスの区分が2つでない { 役割名, 読めた区分の数 } => format!("`{役割名}` に包まれた関数のパスは所有する型とメソッドの2区分であるべきだが{読めた区分の数}区分である"),
            Self::役割に包まれた関数のパスが起点の予約語で始まる { 役割名, 先頭の区分 } => format!("`{役割名}` に包まれた関数のパスが `{先頭の区分}` で始まり所有する型の名前でない"),
            Self::役割に包まれた関数の所有者の実装が同じファイルに無い { 役割名, 所有者名 } => format!("`{役割名}` に包まれた関数の所有者 `{所有者名}` の `impl` の行が同じファイルに無い"),
            Self::エンティティの識別子の関連型が無い { 型名 } => format!("`{型名}` の `Mエンティティ` の実装に `type 識別子 =` の行が無い"),
            Self::役割の型自身の宣言である { 役割名 } => format!("`{役割名}` は関数の役割の型自身の宣言であり、包む関数ポインタからは関係を出さない"),
            Self::保証範囲の外の構文である { 構文 } => 構文.説明(),
            Self::Graphiteの生成物の取り込みである { モジュール名 } => format!("`{モジュール名}` はGraphiteの生成物を取り込むモジュールであり、生成物は設計概念の抽出の対象でない"),
        }
    }
}
