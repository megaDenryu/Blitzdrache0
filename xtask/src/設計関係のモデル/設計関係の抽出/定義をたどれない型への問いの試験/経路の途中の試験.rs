//! 辿る経路の途中の節点が、定義をたどれた節点とモジュールパスが空の節点に割れているとき、経路の問いが不在から反証されず未決定になることを固定する回帰試験。
//!
//! 容器のフィールドの型を使う側から定義へたどれないと、容器の辺は空の節点へ付き、その型から先の辺は定義をたどれた節点に付く。問いの両端はどちらも割れていないため、
//! 問いの側の止めは効かない。止めは経路の探索の側(達した節点の相方が先の辺を持つか)にある。

use super::{定義の型, 抽出して問う, 未解決による未決定か};
use blitz_design_verification::{プリミティブな関係の種類, 原子命題, 設計概念への参照, 項};

const 中継と終点の定義: &str = "pub struct 中継 {\n    先: 終点,\n}\n\npub struct 終点 {\n    値: f32,\n}\n";
const 容器の定義: &str = "pub struct 容器 {\n    中身: 中継,\n}\n";

// 使う側の `容器` から定義のファイルの `終点` へ、保持するの辺を辿って達するかの原子命題。
fn 容器が終点を間接に保持する() -> 原子命題 {
    原子命題::プリミティブな関係の経路が在る {
        主語: 項::名指した概念(設計概念への参照::型として生成する("blitz_esca::使う側", "容器")),
        種類: プリミティブな関係の種類::保持する,
        目的語: 定義の型("終点"),
    }
}

#[test]
fn 途中の型をたどれれば間接の保持が証明される() {
    let 使う側 = format!("use crate::旅行者::中継;\n\n{容器の定義}");
    let 結果 = 抽出して問う(中継と終点の定義, &使う側, 容器が終点を間接に保持する());
    assert!(結果.証明済みか(), "{}", 結果.表記());
}

// 反証: 止めが無いと、容器の辺は空の `中継` で途切れ、`中継` から `終点` への辺は定義をたどれた `中継` に付くため、経路の不在から反証される。
#[test]
fn 途中の型をたどれないとき間接の保持の問いは反証されず未決定になる() {
    let 結果 = 抽出して問う(中継と終点の定義, 容器の定義, 容器が終点を間接に保持する());
    assert!(未解決による未決定か(&結果), "{}", 結果.表記());
}
