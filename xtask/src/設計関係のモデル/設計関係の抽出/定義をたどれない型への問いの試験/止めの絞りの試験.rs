//! 定義をたどれたかだけが違う同じ名前の節点が在るときの止めが、不在から導いた答えにだけ、しかもその相方が問う答えの種類の辺を持つときだけ掛かることを固定する回帰試験。
//! 相方の探し方は左右対称であり、端点が定義をたどれた節点なら空の相方を、端点が空の節点なら定義をたどれた相方を答える。
//! ただし構造の検証器では、空の端点は項から節点を求める段で先に未決定になるため、空の端点の側の相方の探し方は検証器の答えを変えない。
//!
//! 止めを項から節点を求める段で無条件に掛けると、2つの答えを失う。1つは、辺が実際に在って証明できる問いである。もう1つは、関数の署名が引数から作った空の節点が
//! 引数に取るの辺しか持たないのに、署名と関係の無い設計関係の問いまで未決定へ倒れることである。

use super::super::抽出の試験の段取り::原文から設計関係グラフと抽出の欠けを組む;
use super::{モジュールパスが求まっていないための未決定か, 使う側のパス, 定義のパス, 定義の型, 抽出して問う, 規則の定義};
use blitz_design_verification::{原子命題, 検証結果, 欠落が弱める答え, 設計概念への参照, 設計関係の結び付き方, 関数の引数と戻り値の役目, 項};

// 定義のファイルの中で、`歩行の規則` を参照する遷移を宣言する。規則の定義と同じファイルのため、この宣言の表記は定義をたどれる。
const 同じファイルの遷移の宣言: &str = "pub struct 旅行者の現在地 {\n    東: f32,\n}\n\nimpl 旅行者の現在地 {}\n\nconst _: M規則で決まる遷移関数<旅行者の現在地, 歩行の規則> = M規則で決まる遷移関数::生成する(旅行者の現在地::動かす);\n";

// 定義のファイルの遷移が包んだ処理から `歩行の規則` への、その種類の設計関係の原子命題。
fn 定義のファイルの処理から規則へ(種類: 設計関係の結び付き方) -> 原子命題 {
    原子命題::設計関係が在る {
        主語: 項::名指した概念(設計概念への参照::処理として生成する("blitz_esca::旅行者", "動かす").所有者を添える(vec!["旅行者の現在地".to_string()])),
        種類,
        目的語: 定義の型("歩行の規則"),
    }
}

// 反証: 止めを項から節点を求める段に置くと、使う側の空の `歩行の規則` に参照するの辺があるために、在る辺の問いまで未決定になる。
#[test]
fn 同じ名前の空の節点が在っても在る辺の問いは証明される() {
    let 定義 = format!("{規則の定義}\n{同じファイルの遷移の宣言}");
    let 使う側 = "pub struct 別の現在地 {\n    東: f32,\n}\n\nimpl 別の現在地 {}\n\nconst _: M規則で決まる遷移関数<別の現在地, 歩行の規則> = M規則で決まる遷移関数::生成する(別の現在地::動かす);\n";
    let 結果 = 抽出して問う(&定義, 使う側, 定義のファイルの処理から規則へ(関数の引数と戻り値の役目::参照する.設計関係の結び付き方へ写す()));
    assert!(結果.証明済みか(), "{}", 結果.表記());
}

// 反証: 止めを答えの種類で絞らないと、使う側の関数の署名が作った空の `歩行の規則`(引数に取るの辺だけを持つ)のために、変換用の素材にするの不在まで未決定になる。
#[test]
fn 空の節点が問わない答えの辺しか持たなければ不在から反証される() {
    let 定義 = format!("{規則の定義}\n{同じファイルの遷移の宣言}");
    let 結果 = 抽出して問う(&定義, 空の規則を作る使う側, 定義のファイルの処理から規則へ(関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す()));
    assert!(matches!(結果, 検証結果::反証済み(_)), "{}", 結果.表記());
}

// 使う側の関数の署名が、取り込みの無い `歩行の規則` を引数に取り、空の `歩行の規則` の節点を作る。
const 空の規則を作る使う側: &str = "pub fn 規則を受け取る(規則: 歩行の規則) {}\n";

// 空の `歩行の規則` へ、定義をたどれたかだけが違う相方のうち、問う答えの種類の辺を持つものを尋ねた答えの表記。
fn 空の規則の相方(種類: 設計関係の結び付き方) -> Option<String> {
    let 定義 = format!("{規則の定義}\n{同じファイルの遷移の宣言}");
    let 抽出したもの = 原文から設計関係グラフと抽出の欠けを組む(&[(定義のパス, 定義.as_str()), (使う側のパス, 空の規則を作る使う側)]);
    let 空の規則 = 設計概念への参照::型として生成する("", "歩行の規則");
    抽出したもの.グラフ.問う答えを持つ定義をたどれたかだけが違う同じ名前の節点(&空の規則, &[欠落が弱める答え::設計関係(種類)]).map(設計概念への参照::表記)
}

// 反証: 相方を定義をたどれた端点の側からしか探さないと、空の端点の相方が問う答えの辺を持っていても無しを答える。
// 構造の検証器は空の端点を項から節点を求める段で未決定にするため、この問いを直に確かめる。
#[test]
fn 空の端点の相方は定義をたどれた節点が問う答えの辺を持てば見つかる() {
    assert_eq!(空の規則の相方(関数の引数と戻り値の役目::参照する.設計関係の結び付き方へ写す()), Some("blitz_esca::旅行者::歩行の規則".to_string()));
}

// 反証: 空の端点の相方を答えの種類で絞らないと、相方が持たない変換用の素材にするの問いでも相方を答える。
#[test]
fn 空の端点の相方は問う答えの辺を持たなければ見つからない() {
    assert_eq!(空の規則の相方(関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す()), None);
}

// 量化が空の節点を束縛しても、空の端点への問いは不在から反証されず、項から節点を求める段で未決定になる。
#[test]
fn 空の端点への問いは反証されず未決定になる() {
    let 定義 = format!("{規則の定義}\n{同じファイルの遷移の宣言}");
    let 空の規則 = 項::名指した概念(設計概念への参照::型として生成する("", "歩行の規則"));
    let 主語 = 項::名指した概念(設計概念への参照::処理として生成する("blitz_esca::旅行者", "動かす").所有者を添える(vec!["旅行者の現在地".to_string()]));
    let 原子 = 原子命題::設計関係が在る {
        主語,
        種類: 関数の引数と戻り値の役目::参照する.設計関係の結び付き方へ写す(),
        目的語: 空の規則,
    };
    assert!(モジュールパスが求まっていないための未決定か(&抽出して問う(&定義, 空の規則を作る使う側, 原子)));
}
