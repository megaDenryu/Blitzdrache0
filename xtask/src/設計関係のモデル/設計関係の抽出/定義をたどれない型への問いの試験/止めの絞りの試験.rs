//! 定義をたどれたかだけが違う同じ名前のノードが在るときの止めが、不在から導いた答えにだけ、しかもその相方が問う答えの種類のエッジを持つときだけ掛かることを固定する回帰試験。
//! 相方の探し方は左右対称であり、端点が定義をたどれたノードなら空の相方を、端点が空のノードなら定義をたどれた相方を答える。
//! ただし構造の検証器では、空の端点は項からノードを求める段で先に未決定になるため、空の端点の側の相方の探し方は検証器の答えを変えない。
//!
//! 止めを項からノードを求める段で無条件に掛けると、2つの答えを失う。1つは、エッジが実際に在って証明できる問いである。もう1つは、フィールドの型から作った空のノードが
//! 保持するのエッジしか持たないのに、保持すると関係の無い設計関係の問いまで未決定へ倒れることである。

use super::super::抽出の試験の段取り::原文から設計関係グラフと抽出の欠けを組む;
use super::{モジュールパスが求まっていないための未決定か, 使う側のパス, 定義のパス, 定義の型, 抽出して問う, 規則の定義};
use blitz_design_verification::設計関係の有無命題;
use blitz_design_verification::{原子命題, 検証結果, 欠落が弱める答え, 設計概念の識別用情報, 設計関係の結び付き方, 関数の引数と戻り値の役目, 項};

// 定義のファイルの中で、`歩行の規則` を参照する状態遷移を宣言する。規則の定義と同じファイルのため、この宣言の表記は定義をたどれる。
const 同じファイルの状態遷移の宣言: &str = "pub struct 旅行者の現在地 {\n    東: f32,\n}\n\nimpl 旅行者の現在地 {}\n\nconst _: M規則で決まる状態遷移関数<旅行者の現在地, 歩行の規則> = M規則で決まる状態遷移関数::生成する(旅行者の現在地::動かす);\n";

// 定義のファイルの状態遷移が包んだ処理から `歩行の規則` への、その種類の設計関係の原子命題。
fn 定義のファイルの処理から規則へ(結び付き方: 設計関係の結び付き方) -> 原子命題 {
    原子命題::設計関係の有無命題(設計関係の有無命題::生成する(
        項::名指した概念(設計概念の識別用情報::処理として生成する("blitz_esca::旅行者", "動かす").所有者を添える(vec!["旅行者の現在地".to_string()])),
        結び付き方,
        定義の型("歩行の規則"),
    ))
}

// 反証: 止めを項からノードを求める段に置くと、使う側の空の `歩行の規則` に参照するのエッジがあるために、在るエッジの問いまで未決定になる。
#[test]
fn 同じ名前の空のノードが在っても在るエッジの問いは証明される() {
    let 定義 = format!("{規則の定義}\n{同じファイルの状態遷移の宣言}");
    let 使う側 = "pub struct 別の現在地 {\n    東: f32,\n}\n\nimpl 別の現在地 {}\n\nconst _: M規則で決まる状態遷移関数<別の現在地, 歩行の規則> = M規則で決まる状態遷移関数::生成する(別の現在地::動かす);\n";
    let 結果 = 抽出して問う(&定義, 使う側, 定義のファイルの処理から規則へ(関数の引数と戻り値の役目::参照する.設計関係の結び付き方へ写す()));
    assert!(結果.証明済みか(), "{}", 結果.表記());
}

// 反証: 止めを答えの種類で絞らないと、使う側のフィールドが作った空の `歩行の規則`(保持するのエッジだけを持つ)のために、変換用の素材にするの不在まで未決定になる。
#[test]
fn 空のノードが問わない答えのエッジしか持たなければ不在から反証される() {
    let 定義 = format!("{規則の定義}\n{同じファイルの状態遷移の宣言}");
    let 結果 = 抽出して問う(&定義, 空の規則を作る使う側, 定義のファイルの処理から規則へ(関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す()));
    assert!(matches!(結果, 検証結果::反証済み(_)), "{}", 結果.表記());
}

// 使う側の構造体のフィールドが、取り込みの無い `歩行の規則` を持ち、空の `歩行の規則` のノードを作る。
const 空の規則を作る使う側: &str = "pub struct 規則を持つもの {\n    規則: 歩行の規則,\n}\n";

// 空の `歩行の規則` へ、定義をたどれたかだけが違う相方のうち、問う答えの種類のエッジを持つものを尋ねた答えの表記。
fn 空の規則の相方(結び付き方: 設計関係の結び付き方) -> Option<String> {
    let 定義 = format!("{規則の定義}\n{同じファイルの状態遷移の宣言}");
    let 抽出したもの = 原文から設計関係グラフと抽出の欠けを組む(&[(定義のパス, 定義.as_str()), (使う側のパス, 空の規則を作る使う側)]);
    let 空の規則 = 設計概念の識別用情報::型として生成する("", "歩行の規則");
    抽出したもの
        .グラフ()
        .問う答えを持つ定義をたどれたかだけが違う同じ名前のノード(&空の規則, &[欠落が弱める答え::設計関係(結び付き方)])
        .map(設計概念の識別用情報::表記)
}

// 反証: 相方を定義をたどれた端点の側からしか探さないと、空の端点の相方が問う答えのエッジを持っていても無しを答える。
// 構造の検証器は空の端点を項からノードを求める段で未決定にするため、この問いを直に確かめる。
#[test]
fn 空の端点の相方は定義をたどれたノードが問う答えのエッジを持てば見つかる() {
    assert_eq!(空の規則の相方(関数の引数と戻り値の役目::参照する.設計関係の結び付き方へ写す()), Some("blitz_esca::旅行者::歩行の規則".to_string()));
}

// 反証: 空の端点の相方を答えの種類で絞らないと、相方が持たない変換用の素材にするの問いでも相方を答える。
#[test]
fn 空の端点の相方は問う答えのエッジを持たなければ見つからない() {
    assert_eq!(空の規則の相方(関数の引数と戻り値の役目::変換用の素材にする.設計関係の結び付き方へ写す()), None);
}

// 量化が空のノードを束縛しても、空の端点への問いは不在から反証されず、項からノードを求める段で未決定になる。
#[test]
fn 空の端点への問いは反証されず未決定になる() {
    let 定義 = format!("{規則の定義}\n{同じファイルの状態遷移の宣言}");
    let 空の規則 = 項::名指した概念(設計概念の識別用情報::型として生成する("", "歩行の規則"));
    let 主語 = 項::名指した概念(設計概念の識別用情報::処理として生成する("blitz_esca::旅行者", "動かす").所有者を添える(vec!["旅行者の現在地".to_string()]));
    let 原子 = 原子命題::設計関係の有無命題(設計関係の有無命題::生成する(主語, 関数の引数と戻り値の役目::参照する.設計関係の結び付き方へ写す(), 空の規則));
    assert!(モジュールパスが求まっていないための未決定か(&抽出して問う(&定義, 空の規則を作る使う側, 原子)));
}
