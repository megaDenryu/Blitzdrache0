//! 設計解釈マーカーのノード。マーカーの正本は `crates/blitz_design/src/設計解釈マーカー.rs` であり、その1つのモジュールパスをノードの識別子へ与える。
//!
//! マーカーの識別子をここ1箇所で組むのは、上位トレイトの宣言(規則1)とマーカーの実装(規則2)が同じマーカーを指す必要があるためである。
//! 別々に組むと、修飾を書いた実装から出たノードと、無修飾の宣言から出たノードが別のノードになり、`M状態` を実装した型の付いているマーカーが `M不変データ` へ閉じない。
//! 設計語彙のクレートの名前は `ontology_scope` だけが持ち、ここではその名前にモジュールの名前を足してモジュールパスを組む。

use super::ontology_scope::設計語彙のクレート;
use crate::conform::設計オントロジーの規約検査::設計解釈マーカーの一覧::設計解釈マーカー;
use crate::設計関係のモデル::{設計概念の識別子, 設計概念の識別用情報, 設計概念ノード};

/// 設計語彙のクレートの中で、設計解釈マーカーの正本を定義するモジュールの名前。
const マーカーの正本のモジュール: &str = "設計解釈マーカー";

/// 設計解釈マーカーの正本のモジュールパス。
pub fn 設計解釈マーカーの正本のモジュールパス() -> String {
    format!("{設計語彙のクレート}::{マーカーの正本のモジュール}")
}

/// マーカーの名前からノードの識別子を組む。
pub fn 設計解釈マーカーの識別子(名前: &str) -> 設計概念の識別子 {
    設計概念の識別子::Rustの項目として生成する(&設計解釈マーカーの正本のモジュールパス(), 名前)
}

/// マーカーの名前から、そのノードを指す参照を組む。マーカーはトレイトであるため種類はトレイトである。
pub fn 設計解釈マーカーの参照(名前: &str) -> 設計概念の識別用情報 {
    設計概念の識別用情報::トレイトとして生成する(&設計解釈マーカーの正本のモジュールパス(), 名前)
}

/// その名前が設計解釈マーカーの名前か。
pub fn 設計解釈マーカーの名前か(名前: &str) -> bool {
    設計解釈マーカー::全部の一覧().iter().any(|マーカー| マーカー.名前() == 名前)
}

/// 全ての設計解釈マーカーへの参照。検証器は付いているマーカーに含まれうるトレイトの一覧としてこれを受け取り、マーカーの正本の一覧の写しを持たない。
pub fn 設計解釈マーカーの参照一覧() -> Vec<設計概念の識別用情報> {
    設計解釈マーカー::全部の一覧().into_iter().map(|マーカー| 設計解釈マーカーの参照(マーカー.名前())).collect()
}

/// 全ての設計解釈マーカーをトレイトのノードとして並べる。関係へ1件も現れないマーカーもノードとして在る。
pub fn 設計解釈マーカーの概念一覧() -> Vec<設計概念ノード> {
    let モジュールパス = 設計解釈マーカーの正本のモジュールパス();
    設計解釈マーカー::全部の一覧().into_iter().map(|マーカー| 設計概念ノード::トレイトとして生成する(&モジュールパス, マーカー.名前())).collect()
}
