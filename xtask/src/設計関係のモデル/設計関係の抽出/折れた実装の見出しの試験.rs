//! rustfmt が `impl` の見出しを複数の行へ折った形の回帰試験。`impl<...>` の行の後に役割の型のパスだけの行と `{` の行が続く見出しを、
//! 1行の `impl<...> 型<...> {` と同じく役割の型自身の実装として対象外にすることと、対象外にするのが本体を開く `{` の行までであることを固定する。

use super::抽出できなかった理由;
use super::抽出の試験の段取り::{原文から設計関係グラフと抽出の欠けを組む, 役割の使用箇所の試験が使う型の定義, 抽出できなかった理由の説明一覧};

const 役割のパス: &str = "crates/blitz_design/src/射影関数.rs";

const 折れた見出し: &str = "impl<状態: M状態, 結果: M不変データ>\n    M射影関数<状態, 結果>\n{\n";

#[test]
fn 折れた実装の見出しの型のパスの行は役割の使用箇所として読まない() {
    let 原文 = 役割の使用箇所の試験が使う型の定義() + 折れた見出し + "    pub const fn 生成する(関数: fn(&状態) -> 結果) -> Self {\n        Self(関数)\n    }\n}\n";
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[(役割のパス, &原文)]);
    assert!(結果.抽出できなかった行一覧().is_empty(), "{:?}", 抽出できなかった理由の説明一覧(&結果));
    assert!(!結果.設計関係の抽出漏れへ写す().在るか(), "{}", 結果.設計関係の抽出漏れへ写す().説明());
}

#[test]
fn 折れた実装の見出しの本体の中の読めない役割の値は黙って落とさず欠落として数える() {
    let 本体 = "    const 射影: M射影関数<旅行者の現在地, 旅行者の出来事> = 何か.射影();\n}\n";
    let 原文 = 役割の使用箇所の試験が使う型の定義() + 折れた見出し + 本体;
    let 本体の行番号 = 原文.lines().count() - 1;
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[(役割のパス, &原文)]);
    let 読めなかった行一覧: Vec<(usize, &抽出できなかった理由)> = 結果.抽出できなかった行一覧().iter().map(|行| (行.行番号(), 行.理由())).collect();
    assert!(
        matches!(読めなかった行一覧.as_slice(), [(行番号, 抽出できなかった理由::役割の値の右辺が役割の生成する呼び出しでない { 役割名: "M射影関数" })] if *行番号 == 本体の行番号),
        "{読めなかった行一覧:?}"
    );
}
