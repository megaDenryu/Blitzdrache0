//! 関数の役割の型を定義する場所の知識。役割ごとに、その型を定義するモジュールと、役割の型と同じ場所に定義された意味型を答える。
//!
//! 役割の名前と型引数の数は、関数の役割の宣言という事実の形を決めるため `blitz_design_verification` の `関数の役割` が持ち、
//! 型引数の位置ごとに出す設計の関係は役割の定義の知識として同じクレートの定義の式が持つ(Issue #193 の段階2)。
//! ここに残るのは、役割の型と意味型をドメインの型から見分けるための、定義の在り処の知識である(`_doc/設計/設計オントロジー.md` 2.1節・第3節)。
//!
//! この知識を `blitz_design_verification` の `関数の役割` の固有のメソッドへ移さず、xtask のトレイトとして生やすのは、
//! 在り処が設計語彙のクレートの名前(`ontology_scope` の `設計語彙のクレート`)に依存するためである。その名前は抽出器が走査する範囲の知識であり、
//! 抽出器を知らない検証のクレートへ写すと、名前を持つ場所が2つになる。依存の向きは xtask から検証のクレートへの一方だけであり、
//! 在り処の知識は抽出器の側に置く。外部クレートの型へ抽出器の側のメソッドを生やすため、このファイルはトレイトを2つ置く。
//! 参照: `crates/blitz_design/src/function_role.rs`・`crates/blitz_design/src/遷移関数.rs`・`crates/blitz_design/src/出来事も失敗も無い遷移関数.rs`・`crates/blitz_design/src/問い合わせを伴う関数.rs`・
//! `crates/blitz_design/src/規則によらない書き換え関数.rs`。

use super::ontology_scope::設計語彙のクレート;
use crate::設計関係のモデル::設計概念への参照;
use blitz_design_verification::関数の役割;

/// 関数の役割の型と、役割に伴う意味型の定義の在り処。抽出器の側の知識を `関数の役割` のメソッドとして読ませる。
pub trait 関数の役割の定義の在り処 {
    /// その役割の型を定義するモジュールのパス。どの役割も設計語彙のクレートの中に在り、モジュールは役割の形ごとに分かれる。
    fn 役割の型を定義するモジュールのパス(self) -> String;

    /// その役割の型と同じモジュールに定義された意味型の名前。意味型とは、型引数に設計解釈マーカーの境界を持ち、その役割の戻り値の形を固定する型のことである。
    fn 伴う意味型の名前一覧(self) -> &'static [&'static str];
}

/// 設計概念への参照が、処理の役割の層に置かれた設計語彙の型を指すかの見分け。
pub trait 関数の役割の型か意味型の見分け {
    /// その参照が、関数の役割の型か、役割に伴う意味型の節点を指すか。この2つはドメインの型でなく、処理の役割の層に置かれた設計語彙である。
    /// 名前だけで判定せず、定義のモジュールパスと種類まで一致させる。名前だけで判定すると、ドメインのクレートが同じ名前の型を定義したとき、
    /// その型を設計語彙と取り違えるためである。
    fn 関数の役割の型か意味型を指す参照か(&self) -> bool;
}

impl 関数の役割の定義の在り処 for 関数の役割 {
    fn 役割の型を定義するモジュールのパス(self) -> String {
        match self {
            関数の役割::M解釈関数 | 関数の役割::M射影関数 => format!("{設計語彙のクレート}::function_role"),
            関数の役割::M遷移関数 => format!("{設計語彙のクレート}::遷移関数"),
            関数の役割::M遷移が受け取る命令で決まる遷移関数 | 関数の役割::M規則で決まる遷移関数 | 関数の役割::M規則と遷移パラメータで決まる遷移関数 => {
                format!("{設計語彙のクレート}::出来事も失敗も無い遷移関数")
            }
            関数の役割::M問い合わせを伴う遷移関数 | 関数の役割::M規則で決まる問い合わせを伴う遷移関数 | 関数の役割::M問い合わせを伴う評価関数 => {
                format!("{設計語彙のクレート}::問い合わせを伴う関数")
            }
            関数の役割::M規則によらない書き換え関数 => format!("{設計語彙のクレート}::規則によらない書き換え関数"),
        }
    }

    // `遷移成功結果<状態: M状態, イベント: Mイベント>` と `遷移失敗結果<状態: M状態, 失敗: std::error::Error>` が `M遷移関数` に伴い、
    // `問い合わせを伴う遷移成功結果<状態: M状態, 観測: M観測>` が問い合わせを伴う2つの遷移に伴う。問い合わせを伴う遷移が失敗側に使う `遷移失敗結果` は `M遷移関数` の在り処に数える。
    fn 伴う意味型の名前一覧(self) -> &'static [&'static str] {
        match self {
            関数の役割::M遷移関数 => &["遷移成功結果", "遷移失敗結果"],
            関数の役割::M問い合わせを伴う遷移関数 | 関数の役割::M規則で決まる問い合わせを伴う遷移関数 => &["問い合わせを伴う遷移成功結果"],
            関数の役割::M解釈関数
            | 関数の役割::M射影関数
            | 関数の役割::M遷移が受け取る命令で決まる遷移関数
            | 関数の役割::M規則で決まる遷移関数
            | 関数の役割::M規則と遷移パラメータで決まる遷移関数
            | 関数の役割::M問い合わせを伴う評価関数
            | 関数の役割::M規則によらない書き換え関数 => &[],
        }
    }
}

impl 関数の役割の型か意味型の見分け for 設計概念への参照 {
    fn 関数の役割の型か意味型を指す参照か(&self) -> bool {
        関数の役割::全部の一覧().into_iter().any(|役割| {
            let モジュールパス = 役割.役割の型を定義するモジュールのパス();
            std::iter::once(役割.名前())
                .chain(役割.伴う意味型の名前一覧().iter().copied())
                .any(|名前| *self == 設計概念への参照::型として生成する(&モジュールパス, 名前))
        })
    }
}
