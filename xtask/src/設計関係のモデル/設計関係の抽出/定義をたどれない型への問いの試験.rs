//! 型の定義をたどれなかった表記か実装の対象があるとき、定義をたどれた同じ名前の型のノードへの問いが、エッジか付いているマーカーの不在から反証されず未決定になることを固定する回帰試験。
//!
//! 抽出器がある場所から型の定義をたどれないと、そこから導いたエッジか付いているマーカーはモジュールパスが空のノードへ付く。定義をたどれたノードへの問いはその空のノードに触れないため、
//! 止めが無いとエッジか付いているマーカーの不在を答える。止めは構造の検証器の1か所(同じ名前の空のノードが在れば未決定)にあり、この試験は経路ごとにそれを確かめる。
//! 経路は、関係の頭の端点の表記・マーカーの実装の対象・`Mエンティティ` の実装の対象の3つである。規則の本体の途中の表記は
//! `抽出の成果と欠け/規則の本体の途中で定義をたどれない型の試験.rs` が確かめる。どの経路も、取り込みを書いた対照が証明済みになることを並べて確かめる。
//! 辿る経路の途中のノードが割れているときは、子のモジュール `経路の途中の試験` が、止めが問いの答えの種類で絞られていることは `止めの絞りの試験` が確かめる。

