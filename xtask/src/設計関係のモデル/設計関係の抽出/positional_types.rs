//! 位置で並べた本体(タプル構造体・タプルの選択肢)の括弧の中身から、位置ごとの型の表記を読む工程。
//! 依存を持たない純粋な関数であり、受け取るのは括弧の中身、返すのは位置の順に並んだ型の表記の一覧か、区切れないという答えである。
//!
//! 読点で単純に切らないのは、`fn(&状態, &コマンド) -> 結果` や `Vec<A, B>` のように読点が括弧と不等号の内側へ現れるためである。
//! 深さが合わない文字列を空の一覧として返さないのは、それが「フィールドが無い」と読まれて、在るはずの `保持する` を静かに落とすためである。
//! 関数ポインタの戻り値の矢印 `->` の `>` は不等号の深さに数えない。数えると、`fn(&状態) -> 結果` が開いていない不等号を閉じたことになり、
//! 区切れる文字列を区切れないと答えるか、関数の役割の型引数を矢印の位置で早く閉じてしまう。

/// 括弧の中身から、位置ごとの型の表記を読む。括弧と不等号の深さが合わなければ無しである。
pub fn 位置で並べた型の一覧(括弧の中身: &str) -> Option<Vec<String>> {
    let mut 一覧 = Vec::new();
    let mut 始まり = 0usize;
    let mut 深さ = 0i32;
    for (位置, 文字) in 括弧の中身.char_indices() {
        match 文字 {
            '<' | '(' | '[' => 深さ += 1,
            '>' if 戻り値の矢印の不等号か(括弧の中身, 位置) => {}
            '>' | ')' | ']' => 深さ -= 1,
            ',' if 深さ == 0 => {
                一覧.push(括弧の中身[始まり..位置].trim().to_string());
                始まり = 位置 + 1;
            }
            _ => {}
        }
        if 深さ < 0 {
            return None;
        }
    }
    if 深さ != 0 {
        return None;
    }
    一覧.push(括弧の中身[始まり..].trim().to_string());
    Some(一覧.into_iter().filter(|表記| !表記.is_empty()).collect())
}

/// その位置の `>` が、関数ポインタの戻り値の矢印 `->` の一部か。一部なら型引数を閉じる不等号ではない。
pub fn 戻り値の矢印の不等号か(文字列: &str, 不等号の位置: usize) -> bool {
    文字列[..不等号の位置].ends_with('-')
}
