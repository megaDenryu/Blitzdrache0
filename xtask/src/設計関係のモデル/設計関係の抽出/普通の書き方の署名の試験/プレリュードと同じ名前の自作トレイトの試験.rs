//! プレリュードのトレイトと同じ名前の自作トレイト(`trait From`)を、同じファイルに定義して・名前で取り込んで・一括取り込み(`use a::*;`)で持ち込んで使ったとき、
//! 抽出器がどれも標準ライブラリの項目と答えずに自作トレイトの定義へたどり着くことを固定する回帰試験。
//! 一括取り込みはプレリュードの名前を隠す名前を持ち込みうるため、プレリュードの名前であることだけを理由に標準ライブラリと答えると、自作トレイトへの関係を黙って落とす。

use super::super::抽出の試験の段取り::{原文から設計関係グラフと抽出の欠けを組む, 関係の表記一覧};

const 試験のパス: &str = "crates/blitz_game/src/試験.rs";

const 変換のパス: &str = "crates/blitz_game/src/変換.rs";

const 変換の原文: &str = "pub trait From {}\n";

const 形のパス: &str = "crates/blitz_game/src/形.rs";

const 形の原文: &str = "pub struct 地図 {\n    広さ: u8,\n}\n";

const 束のパス: &str = "crates/blitz_game/src/束.rs";

const 束の原文: &str = "pub use crate::形::*;\n";

// 使う側の原文を、変換と形と束のモジュールと並べて抽出し、関係を落とした抽出の欠落の件数と関係の表記一覧と抽出できなかった理由の呼び名の一覧を返す。
fn 抽出する(使う側の原文: &str) -> (usize, Vec<String>, Vec<&'static str>) {
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[(試験のパス, 使う側の原文), (変換のパス, 変換の原文), (形のパス, 形の原文), (束のパス, 束の原文)]);
    let 呼び名一覧 = 結果.抽出できなかった行一覧.iter().map(|行| 行.理由.種別の呼び名()).collect();
    (結果.関係を落とした抽出の欠落へ写す().合計の件数(), 関係の表記一覧(&結果), 呼び名一覧)
}

#[test]
fn 同じファイルに定義した同名の自作トレイトへたどり着く() {
    let (欠落の件数, 表記一覧, _) = 抽出する("pub trait From {}\n\npub fn 使う(値: &dyn From) {}\n");
    assert_eq!(欠落の件数, 0);
    assert!(表記一覧.contains(&"blitz_game::試験::使う 引数に取る blitz_game::試験::From".to_string()), "{表記一覧:?}");
}

#[test]
fn 名前で取り込んだ同名の自作トレイトへたどり着く() {
    let (欠落の件数, 表記一覧, _) = 抽出する("use crate::変換::From;\n\npub fn 使う(値: &dyn From) {}\n");
    assert_eq!(欠落の件数, 0);
    assert!(表記一覧.contains(&"blitz_game::試験::使う 引数に取る blitz_game::変換::From".to_string()), "{表記一覧:?}");
}

// 反証: プレリュードの名前であることだけで標準ライブラリと答えると、一括取り込みが持ち込んだ自作の `From` への関係を落とす。
#[test]
fn 一括取り込みで持ち込んだ同名の自作トレイトへたどり着く() {
    let (欠落の件数, 表記一覧, _) = 抽出する("use crate::変換::*;\n\npub fn 使う(値: &dyn From) {}\n");
    assert_eq!(欠落の件数, 0);
    assert!(表記一覧.contains(&"blitz_game::試験::使う 引数に取る blitz_game::変換::From".to_string()), "{表記一覧:?}");
}

// 反証: 一括取り込みが見えるだけでプレリュードの名前をたどれないと答えると、取り込み元が `From` を定義していなくても標準の `From` を欠落に数え、
// 標準ライブラリのトレイトの実装の関数を除外できなくなる。取り込み元にその名前が確かに無ければ、その一括取り込みからは来ない。
#[test]
fn 一括取り込みの先にプレリュードの名前の定義が無ければ標準ライブラリの項目である() {
    let (欠落の件数, 表記一覧, _) = 抽出する(
        "use crate::形::*;

pub fn 使う(値: &dyn From) {}
",
    );
    assert_eq!(欠落の件数, 0);
    assert!(!表記一覧.iter().any(|表記| 表記.ends_with("From")), "{表記一覧:?}");
}

// 反証: 取り込み元がさらに一括取り込みを持つとき標準ライブラリと答えると、その先が持ち込む自作トレイトへの関係を、黙って消す。
// たどれない名前は、定義のモジュールパスが空の節点への関係と、定義をたどれない1件として残る(触れた命題は検証器が未決定で止める)。
#[test]
fn 一括取り込みの先がさらに一括取り込みを持つなら定義をたどれないままにする() {
    let (_, 表記一覧, 呼び名一覧) = 抽出する(
        "use crate::束::*;

pub fn 使う(値: &dyn From) {}
",
    );
    assert!(表記一覧.contains(&"blitz_game::試験::使う 引数に取る From".to_string()), "{表記一覧:?}");
    assert!(!呼び名一覧.is_empty(), "{呼び名一覧:?}");
}

// 標準ライブラリのモジュールの一括取り込みだけが見えるなら、持ち込まれた名前は標準ライブラリの項目であり、関係も欠落も作らない。
#[test]
fn 標準ライブラリのモジュールの一括取り込みだけなら標準ライブラリの項目である() {
    let (欠落の件数, 表記一覧, _) = 抽出する("use std::fmt::*;\n\npub fn 見せる(値: &dyn Display) {}\n");
    assert_eq!(欠落の件数, 0);
    assert!(!表記一覧.iter().any(|表記| 表記.ends_with("Display")), "{表記一覧:?}");
}
