//! 一括取り込み(`use a::*;`)の取り込み元が、プレリュードのトレイトと同じ名前(`Clone`)を持ち込まないと確かに言えるときだけ、
//! 抽出器がその名前を標準ライブラリの項目と答えることを固定する回帰試験。言えないときは定義をたどれない1件として残し、黙って標準ライブラリにしない。

use super::super::抽出の試験の段取り::{原文から設計関係グラフと抽出の欠けを組む, 関係の表記一覧};

const 試験のパス: &str = "crates/blitz_game/src/試験.rs";

const 形のパス: &str = "crates/blitz_game/src/形.rs";

const 形の原文: &str = "pub struct 地図 {\n    広さ: u8,\n}\n\npub mod 内 {\n    pub struct 地点;\n}\n";

const マクロの中のパス: &str = "crates/blitz_game/src/マクロの中.rs";

const マクロの中の原文: &str = "何かのマクロ! {\n    pub trait Clone {}\n}\n";

// 使う側の原文を、形とマクロの中のモジュールと並べて抽出し、関係を落とした抽出の欠落の件数と関係の表記一覧と抽出できなかった理由の呼び名の一覧を返す。
fn 抽出する(使う側の原文: &str) -> (usize, Vec<String>, Vec<&'static str>) {
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[(試験のパス, 使う側の原文), (形のパス, 形の原文), (マクロの中のパス, マクロの中の原文)]);
    let 呼び名一覧 = 結果.抽出できなかった行一覧.iter().map(|行| 行.理由.種別の呼び名()).collect();
    (結果.関係を落とした抽出の欠落へ写す().合計の件数(), 関係の表記一覧(&結果), 呼び名一覧)
}

// 使う側の原文の `Clone` が、定義をたどれない名前として関係と欠けの1件に残ることを確かめる。
fn 定義をたどれないまま残す(使う側の原文: &str) {
    let (_, 表記一覧, 呼び名一覧) = 抽出する(使う側の原文);
    assert!(表記一覧.contains(&"blitz_game::試験::使う 引数に取る Clone".to_string()), "{表記一覧:?}");
    assert!(呼び名一覧.contains(&"型の定義をたどれずモジュールパスを空にした"), "{呼び名一覧:?}");
}

// 反証: 取り込み元の直下の定義だけを見ると、マクロの呼び出しの中の自作の `Clone` を見落として「確かに無い」と答え、標準ライブラリの `Clone` と取り違える。
#[test]
fn 取り込み元のマクロの呼び出しの中に同じ名前の定義があれば定義をたどれないままにする() {
    定義をたどれないまま残す("use crate::マクロの中::*;\n\npub fn 使う(値: &dyn Clone) {}\n");
}

// 反証: 祖先のファイル(`形.rs`)があるだけで取り込み元が在るとみなすと、実在しないモジュールに何も無いと答え、標準ライブラリの `Clone` と取り違える。
#[test]
fn 取り込み元のモジュールが実在しなければ定義をたどれないままにする() {
    定義をたどれないまま残す("use crate::形::無い子::*;\n\npub fn 使う(値: &dyn Clone) {}\n");
}

// 波括弧付きのモジュールは在るモジュールの一覧に載らないが、本体の行があるため実在すると分かる。そこに `Clone` が確かに無ければ標準ライブラリの項目である。
#[test]
fn 波括弧付きのモジュールの取り込み元に名前が無ければ標準ライブラリの項目である() {
    let (欠落の件数, 表記一覧, _) = 抽出する("use crate::形::内::*;\n\npub fn 使う(値: &dyn Clone) {}\n");
    assert_eq!(欠落の件数, 0);
    assert!(!表記一覧.iter().any(|表記| 表記.ends_with("Clone")), "{表記一覧:?}");
}
