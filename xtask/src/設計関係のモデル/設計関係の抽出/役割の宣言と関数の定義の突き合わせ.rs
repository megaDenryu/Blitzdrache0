//! 役割の宣言と関数の定義の突き合わせ。受け取るのは全ての規則の成果を併せた抽出の成果と抽出対象のソース群、返すのは、関数の役割の宣言の処理を、その関数の署名の事実の処理(関数を定義した位置で組んだ識別子)へ揃えた成果である。
//!
//! 役割の宣言の事実は、処理の識別子を使用箇所のファイルのモジュールパスで組む。関数の署名の事実は、`fn` を書いた位置のモジュール(波括弧付きの `mod` を含む)で組む。
//! 関数を別のファイルの `impl` に置くと2つが食い違い、同じ関数が2つの処理の節点へ割れて、役割が導く設計関係と署名が導く関係が別の節点に付く。
//! 関数の定義の位置を正とするのは、使用箇所がどこであっても関数そのものは1つだからである。
//!
//! 突き合わせる候補は、同じクレートの署名の事実のうち、関数の名前が同じで、所有者の型の定義が役割の宣言の所有者の型の定義と同じものである。
//! 所有者の型の定義は、役割の宣言の行と署名の行のそれぞれから型の名前を解決して求める。名前だけで照らすと、同じクレートの別のモジュールに同じ名前の型が在るとき、
//! その型の同じ名前のメソッドと取り違え、正しい関数の署名を読めなかったときに別の型のメソッドへ黙って結び付くためである。
//! 固有の実装はその型を定義したクレートにしか書けないため、候補を同じクレートに限ってよい。
//!
//! 候補は、固有の実装の関数を先に探し、無ければトレイトの実装の関数を探す。Rust が `型::関数` を固有の実装から先に解決するのと同じ順である。
//! トレイトの実装の関数の署名は所有者の並びへトレイトの表記を含むため、役割の宣言の処理をその署名の処理へ揃えると所有者の並びも揃う。
//! 候補が1つなら揃え、2つ以上なら決められないため役割の宣言を抽出できなかった行に数えて事実を落とす(黙って1つを選ばない)。
//! 候補が無いとき(役割の宣言の所有者の型の定義をたどれないときを含む)は使用箇所で組んだ識別子のまま残す。関数の見出しを読めなかった行は署名の抽出が既に数えており、
//! マクロが作る関数のように見出しがソースに無い関数もあるためである。

use super::抽出できなかった行の定義::{抽出できなかった理由, 抽出できなかった行};
use super::抽出の成果と欠け::抽出の成果;
use super::抽出対象のソース群の定義::抽出対象のソース群;
use blitz_design_verification::{Rustの項目の種類, 事実の出どころ, 修飾の無い名前の解決, 型の名前の解決, 設計概念, 設計概念の識別子, 関数の役割の宣言の事実, 関数の署名の事実};

impl 抽出の成果 {
    /// 関数の役割の宣言の処理を、同じ関数の署名の事実の処理へ揃えた成果。所有者の型の定義を、借りたソース群で名前を解決して照らす。
    pub fn 役割の宣言の処理を関数の定義へ揃える(mut self, ソース群: &抽出対象のソース群) -> Self {
        let 宣言一覧 = std::mem::take(&mut self.事実.関数の役割の宣言一覧);
        for 宣言 in 宣言一覧 {
            let 候補一覧 = self.同じ関数の署名の処理一覧(&宣言, ソース群);
            match 候補一覧.as_slice() {
                [] => self.事実.関数の役割の宣言一覧.push(宣言),
                [定義の処理] => {
                    let 処理 = 定義の処理.clone();
                    self.事実.関数の役割の宣言一覧.push(関数の役割の宣言の事実 { 処理, ..宣言 });
                }
                _ => {
                    let 理由 = 抽出できなかった理由::役割に包まれた関数の定義が一意に決まらない {
                        役割名: 宣言.役割.名前(),
                        関数名: 宣言.処理.識別子().表記(),
                        候補の数: 候補一覧.len(),
                    };
                    self.抽出できなかった行一覧.push(抽出できなかった行::生成する(&宣言.出どころ.パス, 宣言.出どころ.行番号, 理由));
                }
            }
        }
        self
    }

    // 役割の宣言が包んだ関数と同じ関数の署名の処理の一覧。固有の実装の関数が在ればそれだけを、無ければトレイトの実装の関数を並べる。同じ処理が2度並ばない。
    fn 同じ関数の署名の処理一覧(&self, 宣言: &関数の役割の宣言の事実, ソース群: &抽出対象のソース群) -> Vec<設計概念> {
        let 識別子 = 宣言.処理.識別子();
        let Some(所有者の型の在り処) = 所有者の型の定義のモジュールパス(ソース群, 識別子, &宣言.出どころ) else {
            return Vec::new();
        };
        let 同じ所有者の型の署名一覧: Vec<&関数の署名の事実> = self
            .事実
            .関数の署名一覧
            .iter()
            .filter(|署名| {
                let 候補 = 署名.処理.識別子();
                候補.クレート名() == 識別子.クレート名() && 候補.名前 == 識別子.名前 && 候補.所有者の並び.first() == 識別子.所有者の並び.first()
            })
            .filter(|署名| 所有者の型の定義のモジュールパス(ソース群, 署名.処理.識別子(), &署名.出どころ).as_ref() == Some(&所有者の型の在り処))
            .collect();
        let 固有の実装の処理一覧 = 重ならない処理一覧(&同じ所有者の型の署名一覧, 1);
        if 固有の実装の処理一覧.is_empty() {
            重ならない処理一覧(&同じ所有者の型の署名一覧, 2)
        } else {
            固有の実装の処理一覧
        }
    }
}

// 所有者の並びの先頭(所有者の型の名前)を、その行から見た型の定義のモジュールパスへ解決する。所有者を持たないか、定義をたどれなければ無しである。
fn 所有者の型の定義のモジュールパス(ソース群: &抽出対象のソース群, 識別子: &設計概念の識別子, 出どころ: &事実の出どころ) -> Option<String> {
    let 型の名前 = 識別子.所有者の並び.first()?;
    match ソース群.修飾の無い名前を解決する(型の名前, Rustの項目の種類::型, 出どころ) {
        修飾の無い名前の解決::定義がある { モジュールパス } => Some(モジュールパス),
        修飾の無い名前の解決::標準ライブラリの項目である | 修飾の無い名前の解決::定義をたどれない => None,
    }
}

// 所有者の並びの長さがその数である署名の処理を、同じ処理が2度並ばないように集める。固有の実装の関数は1(型)、トレイトの実装の関数は2(型とトレイトの表記)である。
fn 重ならない処理一覧(署名一覧: &[&関数の署名の事実], 所有者の並びの長さ: usize) -> Vec<設計概念> {
    let mut 一覧: Vec<設計概念> = Vec::new();
    for 署名 in 署名一覧.iter().filter(|署名| 署名.処理.識別子().所有者の並び.len() == 所有者の並びの長さ) {
        if !一覧.contains(&署名.処理) {
            一覧.push(署名.処理.clone());
        }
    }
    一覧
}
