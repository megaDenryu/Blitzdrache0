//! 抽出の規則5: 関数の役割の使用箇所から、関数の役割の宣言を抽出する工程。
//! 受け取るのは抽出対象のソース群、返すのは関数の役割の宣言を持つ成果である。関係は出さない(Issue #193 の段階2)。
//!
//! 宣言が持つのは、役割と、型引数の表記を位置の順に並べた一覧と、包まれた関数のノードである。型引数の位置ごとに何を変換用の素材にし何を生成するかは、
//! 役割の定義の知識として定義の式(`blitz_design_verification`)が持つ。
//!
//! 包まれた関数のノードは、役割の値の右辺に包まれている具体の関数のパスから組み、種類は処理である。この1つの決め方だけを持ち、宣言の名前へは退避しない。
//! 右辺の関数を処理にするのは、データの流れが「どの処理が何を変換用の素材にして何を生成するか」であり、役割の値を持つ宣言が
//! その関数が役割の型契約を満たすことをコンパイラに確かめさせるだけの、関数の役割の宣言でしかないためである。宣言の名前を使うと、関数の役割の宣言が処理としてノードに立つ。
//! rustfmt が複数の行へ折った `const` の宣言は `折れた役割の宣言` が1行へ繋いでから読み、出どころは書き出しの行にする。
//! `impl` の見出しは、書き出しの行から本体を開く `{` の行までを1つの見出しとして読み飛ばす。rustfmt が見出しを `impl<...>` の行と型のパスの行と `{` の行へ折ると、
//! 型のパスの行は役割の使用箇所に見えるが、1行の見出しと同じく役割の型自身の実装である。見出しを読めないとき(型引数が閉じない)は1行ずつ読み、黙って外さない。
//! 右辺を読めない形(戻り値の型・フィールドの型注釈・`= 何か.何か()`)からは処理が決まらないため宣言を出さず、`抽出できなかった行` として数える。
//! 受理する右辺の正規形は `役割に包まれた関数のパスの定義` が4つの条件で書き下しており、どれかを満たさない行も `抽出できなかった行` として数える。
//!
//! 型引数は生の `fn f(a: A) -> B` から読まない。読むと関数の引数と戻り値という言語の形がそのまま設計の意味になり、
//! 設計として説明可能かを問う力を失う。読むのは役割の型の使用箇所の型引数だけである。

use super::役割の使用箇所::{役割の使用箇所を読む工程, 役割の使用箇所を読んだ結果};
use super::折れた役割の宣言::折れた役割の宣言;
use super::抽出できなかった行の定義::抽出できなかった行;
use super::抽出の成果と欠け::抽出の成果;
use super::抽出対象のソース群の定義::抽出対象のソース群;
use crate::conform::設計オントロジーの規約検査::impl_header::implの見出しを読む;
use crate::設計関係のモデル::{Rustの項目の種類, 設計概念ノード};
use blitz_design_verification::{型の表記, 宣言の出どころ, 関数の役割の宣言};

pub fn 関数の役割の型引数から抽出する(ソース群: &抽出対象のソース群) -> 抽出の成果 {
    let mut 成果 = 抽出の成果::default();
    for (パス, 行一覧) in ソース群.ファイル一覧() {
        let モジュールパス = ソース群.ファイルのモジュールパス(パス);
        let 読む工程 = 役割の使用箇所を読む工程::生成する(行一覧);
        let mut 添字 = 0;
        while let Some(行) = 行一覧.get(添字) {
            if let Some(見出し) = implの見出しを読む(行一覧, 添字) {
                添字 += 見出し.占める行の数();
                continue;
            }
            let 折れた文 = 折れた役割の宣言::書き出しの行から繋ぐ(行一覧, 添字);
            let 読んだ結果 = 読む工程.行から読む(折れた文.as_ref().map_or(行.as_str(), |文| 文.本文()));
            match 読んだ結果 {
                役割の使用箇所を読んだ結果::使用箇所でない => {}
                役割の使用箇所を読んだ結果::読めた {
                    役割, 包まれた関数のパス, 型引数の表記一覧
                } => 成果.関数の役割の宣言を足す(関数の役割の宣言::生成する(
                    設計概念ノード::Rustの項目として生成する(包まれた関数のパス.処理の識別子を組む(&モジュールパス), Rustの項目の種類::処理),
                    役割,
                    型引数の表記一覧.iter().map(|表記| 型の表記::型引数の無い場所で生成する(表記)).collect(),
                    宣言の出どころ::生成する(パス.clone(), 添字 + 1),
                )),
                役割の使用箇所を読んだ結果::読めなかった(理由) => 成果.抽出できなかった行一覧を足す([抽出できなかった行::生成する(パス, 添字 + 1, 理由)]),
            }
            添字 += 折れた文.map_or(1, |文| 文.行の数());
        }
    }
    成果
}
