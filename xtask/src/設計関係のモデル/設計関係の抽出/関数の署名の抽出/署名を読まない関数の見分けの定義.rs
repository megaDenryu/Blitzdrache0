//! 署名を読まない関数の見分け。1つのファイルの項目の位置の関数について、関数の署名の事実にせず明示して外すか(設計語彙のクレートの関数か、
//! 標準ライブラリのトレイトの実装の関数か)を答える。受け取るのは関数を書いた場所と、その `fn` の行、返すのは外す理由か無しである。
//!
//! トレイトが標準ライブラリのものかは、定義の式と同じ定義の探索の口で見分ける(`抽出対象のソース群::トレイトの表記が標準ライブラリのトレイトを指すか`)。
//! この解決は実装の見出し1つにつき1回だけ行う。同じ実装の本体の関数は同じ答えになり、関数ごとに解決し直すと、実装が持つ関数の数だけ
//! 型の定義の探索(全ファイルの走査)を繰り返すためである。同じ本体の関数は続けて現れるため、直前に答えた本体とその答えを1つ控えれば足りる。

use std::path::Path;

use super::super::ontology_scope::設計語彙のクレート;
use super::super::抽出できなかった行の定義::署名を読まない関数;
use super::super::抽出対象のソース群の定義::抽出対象のソース群;
use super::super::関数を持つ位置::関数を書いた場所;
use crate::conform::設計オントロジーの規約検査::line_matching::クレート名;
use blitz_design_verification::事実の出どころ;

/// 1つのファイルの関数を見分ける係。ソース群とファイルのパスと、直前に答えた実装の本体の答えを保持する。
pub struct 署名を読まない関数の見分け<'a> {
    ソース群: &'a 抽出対象のソース群,
    パス: &'a Path,
    設計語彙のファイルか: bool,
    直前の本体の答え: Option<(実装の本体の鍵, Option<String>)>,
}

/// 実装の本体を見分ける鍵。位置のモジュールと、処理の識別子へ添える所有者の名前の並び(対象の型とトレイトの表記)の組である。
/// 同じモジュールで同じ型へ同じトレイトを2度実装することは rustc が拒むため、この組は実装の本体を1つに決める。
#[derive(PartialEq, Eq)]
struct 実装の本体の鍵 {
    モジュールパス: String,
    所有者の名前一覧: Vec<String>,
}

impl<'a> 署名を読まない関数の見分け<'a> {
    pub fn 生成する(ソース群: &'a 抽出対象のソース群, パス: &'a Path) -> Self {
        Self {
            ソース群,
            パス,
            設計語彙のファイルか: クレート名(パス) == 設計語彙のクレート,
            直前の本体の答え: None,
        }
    }

    /// 項目の位置の関数を署名を読まずに外すなら、その理由。場所は項目の位置でなければ無しであり、そのときは外さない(項目の位置でない関数として別に数える)。
    pub fn 見分ける(&mut self, 場所: Option<&関数を書いた場所>, 添字: usize) -> Option<署名を読まない関数> {
        if self.設計語彙のファイルか {
            return Some(署名を読まない関数::設計語彙のクレートの関数);
        }
        let トレイト = self.標準ライブラリのトレイトの表記(場所?, 添字)?;
        Some(署名を読まない関数::標準ライブラリのトレイトの実装の関数 { トレイト })
    }

    // 関数を囲む本体が標準ライブラリのトレイトの実装なら、そのトレイトの表記。直前に答えた本体と同じなら、控えた答えを返して解決し直さない。
    fn 標準ライブラリのトレイトの表記(&mut self, 場所: &関数を書いた場所, 添字: usize) -> Option<String> {
        let トレイト = 場所.本体.実装したトレイトの表記.as_deref()?;
        let 鍵 = 実装の本体の鍵 {
            モジュールパス: 場所.モジュールパス.表記().to_string(),
            所有者の名前一覧: 場所.本体.所有者の名前一覧.clone(),
        };
        if let Some((_, 答え)) = self.直前の本体の答え.as_ref().filter(|(控えた鍵, _)| *控えた鍵 == 鍵) {
            return 答え.clone();
        }
        let 出どころ = 事実の出どころ {
            パス: self.パス.to_path_buf(),
            行番号: 添字 + 1,
        };
        let 答え = self.ソース群.トレイトの表記が標準ライブラリのトレイトを指すか(トレイト, &出どころ).then(|| トレイト.to_string());
        self.直前の本体の答え = Some((鍵, 答え.clone()));
        答え
    }
}
