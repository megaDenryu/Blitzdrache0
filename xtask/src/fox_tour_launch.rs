//! クソゲー1本目「キツネの場所巡り」の世界を開くための共通の起動指定。担当するのは、シーン名とアセットルートと
//! ストリーミングの指定を1箇所へ置くことだけである。ゲームの操作の出どころもフレーム数もここは決めない。
//!
//! 遊ぶ入口と検収の入口が同じ1箇所を読むのは、2つが違う条件で世界を開くと、検収が通った条件と遊んだ条件が
//! 別物になるためである。先読み半径2は3×3の世界の全チャンクを常駐させるため、遠くの目印がプレイ中に消えることがない。

use std::process::Command;

/// 起動時に読むキツネのシーンの安定ID。この綴りが、キツネを束0のスキン付き描画対象として読むことと、
/// 地形の空と間接照明と自動露出を選ぶことと、書き換えもピクセル判定も持たない検収計画を選ぶことを同時に決める。
pub(crate) const シーン名: &str = "terrain_fox_tour";

const アセットルート: &str = "target/fox_tour_assets";
const 先読み半径: &str = "2";

/// ストリーミングの容量上限。9チャンクの実行時形式は合計およそ4メガバイトであり、縮退させずに全件を常駐させる値を置く。
const 容量上限バイト: &str = "16777216";

/// この世界を開くための指定をコマンドへ積む。積むのは世界の指定だけであり、ゲームの選択と実行の終わり方は呼び出し側が積む。
pub(crate) fn 世界を開く指定を積む(コマンド: &mut Command) {
    コマンド
        .args(["--scene", シーン名])
        .args(["--asset-root", アセットルート])
        .args(["--streaming", "--streaming-preload-radius", 先読み半径])
        .args(["--streaming-ram-limit", 容量上限バイト])
        .args(["--streaming-vram-limit", 容量上限バイト]);
}
