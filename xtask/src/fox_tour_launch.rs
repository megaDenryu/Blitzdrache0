//! クソゲー1本目「キツネの場所巡り」の世界を開くための共通の起動材料。担当するのは、シーン名とアセットルートと
//! ストリーミングの指定を1箇所へ置くことだけである。ゲームの操作の出どころもフレーム数もここは決めない。
//!
//! 遊ぶ入口と検収の入口が同じ1箇所を読むのは、2つが違う条件で世界を開くと、検収が通った条件と遊んだ条件が
//! 別物になるためである。先読み半径2は3×3の世界の全チャンクを常駐させるため、遠くの目印がプレイ中に消えることがない。

use std::path::PathBuf;

use blitz_asset_compiler::実行時形式の出力ルート;

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 世界を読ませて報告を採る実行環境, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収エラー,
    検収シーン名,
};

/// 起動時に読むキツネのシーンの安定ID。この綴りが、キツネを束0のスキン付き描画対象として読むことと、
/// 地形の空と間接照明と自動露出を選ぶことと、書き換えもピクセル判定も持たない検収計画を選ぶことを同時に決める。
pub(crate) const シーン名: 検収シーン名 = 検収シーン名::生成する("terrain_fox_tour");

const アセットルート: &str = "target/fox_tour_assets";
const 先読み半径: &str = "2";

/// ストリーミングの容量上限。9チャンクの実行時形式は合計およそ4メガバイトであり、縮退させずに全件を常駐させる値を置く。
const 容量上限バイト: &str = "16777216";

pub(crate) fn 場所巡りの世界を遊ぶ実行時形式の出力ルート() -> 実行時形式の出力ルート {
    実行時形式の出力ルート::ディレクトリを作らずに指す(PathBuf::from(アセットルート))
}

/// 検収がこの世界を撮るための実行環境。
pub(crate) fn 場所巡りの世界の検収の実行環境を作る(
    出力ディレクトリ: PathBuf,
) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::綴りから生成する(アセットルート),
        出力ディレクトリ,
    )
}

/// 人がこの世界を遊ぶための実行環境。リリース版を構築させるのは、遊ぶ側が速さを要るためである。
pub(crate) fn 場所巡りの世界を遊ぶ実行環境を作る() -> 世界を読ませて報告を採る実行環境 {
    世界を読ませて報告を採る実行環境::作る(
        アプリの起こし方::毎回cargoにリリース版を構築させて起動する,
        実行時アセットルート::綴りから生成する(アセットルート),
    )
}

/// 枚数を決めて撮る起動の指定。世界を開く指定までを積み、ゲームの選択は呼び出し側が続けて足す。
pub(crate) fn 枚数を決めて世界を開く(フレーム数: 描画フレーム数) -> アプリの起動指定 {
    ストリーミングを積む(アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数))
}

/// 人が閉じるまで遊ぶ起動の指定。
pub(crate) fn 人が終えるまで世界を開く() -> アプリの起動指定 {
    ストリーミングを積む(アプリの起動指定::シーンを決めて人が終えるまで描かせる(シーン名))
}

fn ストリーミングを積む(指定: アプリの起動指定) -> アプリの起動指定 {
    指定
        .選択肢を足す("--streaming")
        .値を持つ選択肢を足す("--streaming-preload-radius", 先読み半径)
        .値を持つ選択肢を足す("--streaming-ram-limit", 容量上限バイト)
        .値を持つ選択肢を足す("--streaming-vram-limit", 容量上限バイト)
}
