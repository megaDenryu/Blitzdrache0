//! 追跡している文書(`.gltf`)の、生成を起こす直前の写し。受け取るのはソースルート、
//! 返すのは生成の後に中身が変わった文書の一覧である。
//!
//! 正本は生成器のコードと生成の入力であり、追跡している文書は「追跡された生成のスナップショット」である。
//! 追跡するのはレビューで差分を読むためであって、正本だからではない。したがって、生成の後に文書の中身が
//! 変わったなら、それは正本が変わったのにスナップショットが更新されていない状態である。黙って進まず落とす。
//!
//! 判定をGitの状態でなく生成の前後のバイトの一致で行うのは、Gitの外(cloneせずに置いた木・別の版管理)でも
//! 同じ判定にするためである。
//!
//! 新しく現れた文書を食い違いに数えないのは、それが「無かったものが生成された」だけであり、
//! スナップショットが古いことを意味しないためである。
//!
//! 畳んだ内容ハッシュを出すのは、生成の指紋がこれを材料に取るためである。人が手で文書を書き換えた場面は、
//! この値が変わることで生成器が起き、そのうえで前後の比較が食い違いを名指す。
//!
//! 表の鍵をソースルートからの相対のパスにするのは、置き場の絶対の綴りが機械ごとに違い、畳んだ値が
//! 中身と無関係に変わるためである。

use std::collections::BTreeMap;
use std::path::PathBuf;

use blitz_asset_compiler::{ソースルート, 内容ハッシュ};

use super::error::生成物のソースアセットの取り揃えの破れ;
use crate::file_scan;

const 文書の拡張子: &str = "gltf";

pub(super) struct 生成の直前の文書の写し(BTreeMap<PathBuf, 内容ハッシュ>);

impl 生成の直前の文書の写し {
    pub(super) fn ソースルートの下でいま撮る(
        ソースルート: &ソースルート,
    ) -> Result<Self, 生成物のソースアセットの取り揃えの破れ> {
        文書ごとの内容ハッシュを集める(ソースルート).map(Self)
    }

    /// 全部の文書の中身を並び順の決まった1つの値へ畳む。
    pub(super) fn 畳んだ内容ハッシュ(&self) -> 内容ハッシュ {
        let 綴り: String = self
            .0
            .iter()
            .map(|(パス, ハッシュ)| {
                format!(
                    "{}={}
",
                    パス.display(),
                    ハッシュ.十六進の綴りを作る()
                )
            })
            .collect();
        内容ハッシュ::バイト列から求める(綴り.as_bytes())
    }

    /// 生成の後にもう一度読み、写しと中身が違う文書を全部名指す。食い違いが無ければ、生成の後の畳んだ値を返す。
    /// 返すのは、台帳へ書く指紋が生成の後の状態を材料にするためである。
    pub(super) fn 生成の後の食い違いを確かめる(
        &self,
        ソースルート: &ソースルート,
    ) -> Result<内容ハッシュ, 生成物のソースアセットの取り揃えの破れ> {
        let 生成の後 = 文書ごとの内容ハッシュを集める(ソースルート)?;
        let 食い違ったパス一覧: Vec<PathBuf> = self
            .0
            .iter()
            .filter(|(パス, 生成の前のハッシュ)| 生成の後.get(*パス).is_some_and(|後| 後 != *生成の前のハッシュ))
            .map(|(パス, _)| パス.clone())
            .collect();
        if 食い違ったパス一覧.is_empty() {
            Ok(Self(生成の後).畳んだ内容ハッシュ())
        } else {
            Err(生成物のソースアセットの取り揃えの破れ::追跡している文書が生成結果と食い違った {
                食い違ったパス一覧,
            })
        }
    }
}

fn 文書ごとの内容ハッシュを集める(
    ソースルート: &ソースルート,
) -> Result<BTreeMap<PathBuf, 内容ハッシュ>, 生成物のソースアセットの取り揃えの破れ> {
    let 走査の起点 = ソースルート.ファイル走査へ貸すディレクトリ().to_string_lossy().into_owned();
    let 一覧 =
        file_scan::対象ファイル一覧を集める(&[&走査の起点], &[文書の拡張子]).map_err(生成物のソースアセットの取り揃えの破れ::文書の走査に失敗した)?;
    let mut 表 = BTreeMap::new();
    for パス in 一覧 {
        let ハッシュ = 内容ハッシュ::ファイルの中身から求める(&パス).map_err(生成物のソースアセットの取り揃えの破れ::文書の中身を読めなかった)?;
        表.insert(ソースルートからの相対にする(ソースルート, パス), ハッシュ);
    }
    Ok(表)
}

/// 走査が返す綴りからソースルートの前置きを落とす。落とせない綴りはそのまま鍵にする。
fn ソースルートからの相対にする(ソースルート: &ソースルート, パス: PathBuf) -> PathBuf {
    match パス.strip_prefix(ソースルート.ファイル走査へ貸すディレクトリ()) {
        Ok(相対) => 相対.to_path_buf(),
        Err(_) => パス,
    }
}
