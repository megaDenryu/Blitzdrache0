//! 生成の指紋: いまの生成器と生成の入力と、追跡している文書の中身を並べた3つの値。受け取るのは生成器の実行ファイルの
//! 内容ハッシュと場所巡りの世界の乱数の種と文書の畳んだ内容ハッシュ、返すのは記録と見比べた新しさである。
//!
//! 3つを1つの値へ再び畳まず構造体のまま比べるのは、畳むと「何が変わったか」が消え、生成器を起こす理由を人へ言えなく
//! なるためである。生成台帳の見出しが同じ形を採っている。
//! 参照: `crates/blitz_asset_compiler/src/generation_ledger/heading.rs`
//!
//! 生成器の実行ファイルの中身を材料にするのは、生成規則を書き換えれば実行ファイルの中身が必ず変わるためである。
//! 人が上げ忘れうる版番号と違い、書き換えを取りこぼさない。これも見出しに倣う。
//!
//! 追跡している文書の中身も材料にするのは、人が手で文書を書き換えた場面を拾うためである。生成器と入力だけを
//! 材料にすると、その書き換えでは指紋が変わらず、共有バッファも在るため生成器が起きず、正本とスナップショットの
//! 食い違いが黙って残る。文書を材料に入れると生成器が起き、生成結果と写しの比較がその食い違いを名指す。
//!
//! 台帳のテキストの綴りは`fingerprint_ledger`が持つ。

use blitz_asset_compiler::{マップ生成の乱数の種, 内容ハッシュ};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 生成の指紋 {
    生成器の実行ファイルの内容ハッシュ: 内容ハッシュ,
    場所巡りの世界の種: マップ生成の乱数の種,
    追跡している文書のダイジェスト: 内容ハッシュ,
}

/// 記録された指紋といまの指紋を見比べた結果。生成器を起こす理由をそのまま人へ言えるよう、
/// 「一致しない」を1つの枝へ畳まず、どの材料が変わったかで分ける。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 指紋の新しさ {
    一致する,
    台帳が無い,
    生成器が変わった,
    種が変わった,
    追跡している文書が変わった,
}

impl 指紋の新しさ {
    pub(super) fn 一致するか(self) -> bool {
        matches!(self, Self::一致する)
    }

    pub(super) fn 説明(self) -> &'static str {
        match self {
            Self::一致する => "指紋が一致している",
            Self::台帳が無い => "生成の指紋の台帳が無い",
            Self::生成器が変わった => "生成器の実行ファイルの中身が変わった",
            Self::種が変わった => "場所巡りの世界の乱数の種が変わった",
            Self::追跡している文書が変わった => "追跡している文書の中身が変わった",
        }
    }
}

impl 生成の指紋 {
    pub(super) fn 三つの材料から組む(
        生成器の実行ファイルの内容ハッシュ: 内容ハッシュ,
        場所巡りの世界の種: マップ生成の乱数の種,
        追跡している文書のダイジェスト: 内容ハッシュ,
    ) -> Self {
        Self {
            生成器の実行ファイルの内容ハッシュ,
            場所巡りの世界の種,
            追跡している文書のダイジェスト,
        }
    }

    /// 生成の後の文書で作り直した指紋。台帳へ書くのはこちらである。生成器が文書も書き直すため、生成の前の状態で
    /// 書くと、次の実行が「文書が変わった」と読んで毎回起こすことになる。
    pub(super) fn 文書のダイジェストを差し替える(self, 追跡している文書のダイジェスト: 内容ハッシュ) -> Self {
        Self {
            追跡している文書のダイジェスト,
            ..self
        }
    }

    pub(super) fn 記録と見比べる(self, 記録: Option<Self>) -> 指紋の新しさ {
        let Some(記録) = 記録 else {
            return 指紋の新しさ::台帳が無い;
        };
        if 記録.生成器の実行ファイルの内容ハッシュ != self.生成器の実行ファイルの内容ハッシュ {
            return 指紋の新しさ::生成器が変わった;
        }
        if 記録.場所巡りの世界の種 != self.場所巡りの世界の種 {
            return 指紋の新しさ::種が変わった;
        }
        if 記録.追跡している文書のダイジェスト != self.追跡している文書のダイジェスト {
            return 指紋の新しさ::追跡している文書が変わった;
        }
        指紋の新しさ::一致する
    }

    pub(super) fn 生成器の実行ファイルの内容ハッシュ(self) -> 内容ハッシュ {
        self.生成器の実行ファイルの内容ハッシュ
    }

    pub(super) fn 場所巡りの世界の種(self) -> マップ生成の乱数の種 {
        self.場所巡りの世界の種
    }

    pub(super) fn 追跡している文書のダイジェスト(self) -> 内容ハッシュ {
        self.追跡している文書のダイジェスト
    }
}
