//! 生成の指紋: いまの生成器と生成の入力と、追跡している文書の中身を1つの値へ畳んだもの。受け取るのは生成器の
//! 実行ファイルの内容ハッシュと場所巡りの世界の乱数の種と文書の畳んだ内容ハッシュ、返すのは畳んだ1つの値である。
//!
//! 共有バッファが在るかどうかだけを見ると、生成器のコードや生成規則を変えた後も古い共有バッファを読み続ける。
//! 共有バッファはGitの追跡に入っていないため、その食い違いは差分にも現れない。だから在るかどうかでなく、
//! いまの生成器といまの入力に対して新しいかどうかを見る。
//!
//! 生成器の実行ファイルの中身を材料にするのは、生成規則を書き換えれば実行ファイルの中身が必ず変わるためである。
//! 人が上げ忘れうる版番号と違い、書き換えを取りこぼさない。この判断は生成台帳の見出しに倣う。
//! 参照: `crates/blitz_asset_compiler/src/generation_ledger/heading.rs`
//!
//! 追跡している文書の中身も材料にするのは、人が手で文書を書き換えた場面を拾うためである。生成器と入力だけを
//! 材料にすると、その書き換えでは指紋が変わらず、共有バッファも在るため生成器が起きず、正本とスナップショットの
//! 食い違いが黙って残る。文書を材料に入れると生成器が起き、生成結果と写しの比較がその食い違いを名指す。

use blitz_asset_compiler::{マップ生成の乱数の種, 内容ハッシュ};

/// 実行ファイルの内容ハッシュと種を1つの綴りへ並べるときの区切り。値の境目を無くさないために置く。
const 材料の区切り: char = ':';

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub(super) struct 生成の指紋(内容ハッシュ);

/// 生成のたびに変わらない材料。文書の中身だけが生成の前後で変わるため、それを添える口を分けて持つ。
pub(super) struct 生成の指紋の材料 {
    生成器の実行ファイルの内容ハッシュ: 内容ハッシュ,
    場所巡りの世界の種: マップ生成の乱数の種,
}

impl 生成の指紋の材料 {
    pub(super) fn 生成器の実行ファイルと種から組む(
        生成器の実行ファイルの内容ハッシュ: 内容ハッシュ,
        場所巡りの世界の種: マップ生成の乱数の種,
    ) -> Self {
        Self {
            生成器の実行ファイルの内容ハッシュ,
            場所巡りの世界の種,
        }
    }

    pub(super) fn 文書を添えて指紋を作る(&self, 文書の畳んだ内容ハッシュ: 内容ハッシュ) -> 生成の指紋 {
        let 材料 = format!(
            "{}{材料の区切り}{}{材料の区切り}{}",
            self.生成器の実行ファイルの内容ハッシュ.十六進の綴りを作る(),
            self.場所巡りの世界の種.値(),
            文書の畳んだ内容ハッシュ.十六進の綴りを作る()
        );
        生成の指紋(内容ハッシュ::バイト列から求める(材料.as_bytes()))
    }
}

impl 生成の指紋 {
    pub(super) fn 十六進の綴りを作る(self) -> String {
        self.0.十六進の綴りを作る()
    }

    pub(super) fn 十六進の綴りから復元する(綴り: &str) -> Option<Self> {
        内容ハッシュ::十六進の綴りから復元する(綴り).map(Self)
    }
}
