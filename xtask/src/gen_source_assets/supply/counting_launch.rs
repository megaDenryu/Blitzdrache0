//! 試験のための偽の起こし係。起こされた回数を数え、作るときに渡した指定に従って共有バッファの空ファイルを置く。
//!
//! 実物の起こし方を試験で使わないのは、cargoの子プロセスと数十件のファイルの書き出しに依存すると、
//! 「揃っているときに起こさない」という不変条件そのものを見分けられなくなるためである。
//!
//! 書き出しの失敗を握り潰さず生成器の失敗として返すのは、置けなかったことを「揃わなかった」と読み違えると、
//! 試験が別の理由で落ちて原因を指さなくなるためである。

use std::cell::Cell;
use std::path::{Path, PathBuf};

use blitz_asset_compiler::{ソースアセットの相対パス, マップ生成の乱数の種};

use super::buffer_group::{場所巡りの世界の共有バッファ, 検証用の世界一式の共有バッファ};
use super::generator_launch::ソースアセットの生成器を起こす係;
use crate::asset_generator::生成器エラー;

/// 失敗の文面がどの生成器かを名指すための名前。実物のexample名と取り違えないよう試験の偽物だと言う。
const 偽の生成器の名前: &str = "試験のための偽の生成器";

pub(super) struct 起こされた回数を数える偽の起こし係 {
    pub(super) ソースルートのパス: PathBuf,
    pub(super) 共有バッファを書くか: bool,
    pub(super) 検証用の世界一式を起こした回数: Cell<u32>,
    pub(super) 場所巡りの世界を起こした回数: Cell<u32>,
}

impl ソースアセットの生成器を起こす係 for 起こされた回数を数える偽の起こし係 {
    fn 検証用の世界一式を書き出す(&self) -> Result<(), 生成器エラー> {
        self.検証用の世界一式を起こした回数.set(self.検証用の世界一式を起こした回数.get() + 1);
        self.頼まれた共有バッファを書く(&検証用の世界一式の共有バッファ)
    }

    fn 場所巡りの世界を種から書き出す(&self, _種: マップ生成の乱数の種) -> Result<(), 生成器エラー> {
        self.場所巡りの世界を起こした回数.set(self.場所巡りの世界を起こした回数.get() + 1);
        self.頼まれた共有バッファを書く(&場所巡りの世界の共有バッファ)
    }
}

impl 起こされた回数を数える偽の起こし係 {
    pub(super) fn 一式と場所巡りを起こした回数(&self) -> (u32, u32) {
        (self.検証用の世界一式を起こした回数.get(), self.場所巡りの世界を起こした回数.get())
    }

    /// 揃っている状態を試験が作るためにも使う。中身は読まれないため空のファイルを置く。
    pub(super) fn 空の共有バッファを置く(
        ソースルートのパス: &Path, 一覧: &[ソースアセットの相対パス]
    ) -> std::io::Result<()> {
        for 相対パス in 一覧 {
            let パス = ソースルートのパス.join(相対パス.綴りを見せる());
            if let Some(収める場所) = パス.parent() {
                std::fs::create_dir_all(収める場所)?;
            }
            std::fs::write(&パス, b"")?;
        }
        Ok(())
    }

    fn 頼まれた共有バッファを書く(&self, 一覧: &[ソースアセットの相対パス]) -> Result<(), 生成器エラー> {
        if !self.共有バッファを書くか {
            return Ok(());
        }
        Self::空の共有バッファを置く(&self.ソースルートのパス, 一覧).map_err(|誤り| 生成器エラー::生成器を起こせなかった {
            生成器: 偽の生成器の名前,
            誤り,
        })
    }
}
