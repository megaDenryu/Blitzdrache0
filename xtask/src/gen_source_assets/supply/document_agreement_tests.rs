//! 追跡している文書が生成結果と食い違わない場面の検査。生成器が同じ中身を書き直したときと、生成の前に無かった
//! 文書が生成の後に現れたときは、どちらも食い違いにならず正常に終わることを固定する。
//!
//! この2件を置くのは、比較を「生成の前後の両方に在れば食い違い」へ弱めても、食い違いの側の検査だけでは
//! 気づけないためである。食い違いが出る場面は`mismatch_tests`が持つ。

#![allow(clippy::unwrap_used)]

use blitz_asset_compiler::ソースアセットの相対パス;

use super::counting_launch::起こされた回数を数える偽の起こし係;
use super::test_scene::{使い捨ての場面, 偽の生成器の振る舞い};

/// 生成器が書く中身。追跡していた中身と同じ綴りを使い、書き直しても食い違わない場面を作る。
const 生成器が書く文書の中身: &str = "板の文書";

#[test]
fn 生成器が同じ中身を書き直しても食い違いにしない() {
    let 場面 = 使い捨ての場面::組み立てる(偽の生成器の振る舞い::最初の生成器が板の文書を書き直す(
        生成器が書く文書の中身,
    ))
    .unwrap();
    起こされた回数を数える偽の起こし係::文書か共有バッファを書く(
        場面.ソースルートのパス(),
        ソースアセットの相対パス::板,
        生成器が書く文書の中身.as_bytes(),
    )
    .unwrap();
    let 結果 = 場面.揃える係().不足していれば生成して揃える();
    let 回数 = 場面.一式と場所巡りを起こした回数();
    場面.片づける().unwrap();
    assert!(結果.is_ok(), "同じ中身なのに食い違いとして落ちた: {:?}", 結果.err());
    assert_eq!(回数, (1, 1), "台帳が無いのに起こしていない");
}

#[test]
fn 生成の前に無く生成の後に現れた文書は食い違いにしない() {
    let 場面 = 使い捨ての場面::組み立てる(偽の生成器の振る舞い::最初の生成器が板の文書を書き直す(
        生成器が書く文書の中身,
    ))
    .unwrap();
    let 結果 = 場面.揃える係().不足していれば生成して揃える();
    let 回数 = 場面.一式と場所巡りを起こした回数();
    場面.片づける().unwrap();
    assert!(結果.is_ok(), "新しく現れた文書を食い違いとして落とした: {:?}", 結果.err());
    assert_eq!(回数, (1, 1), "台帳が無いのに起こしていない");
}
