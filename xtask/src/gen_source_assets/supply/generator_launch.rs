//! ソースアセットの生成器の起こし方。受け取るのは何を書き出させるか、返すのは起こした結果である。
//!
//! 起こし方をトレイトにするのは、揃える工程の試験が生成器の実行そのものを差し替えるためである。実物を起こすと
//! 試験がcargoの子プロセスとファイルの書き出しに依存し、揃っているときに起こさないという不変条件を固定できない。
//!
//! 実物の側が`asset_generator`のセッション型をそのまま通すのは、起こす手順の正本があちらにあるためである。

use blitz_asset_compiler::{マップ生成の乱数の種, 内容ハッシュ};

use super::error::生成物のソースアセットの取り揃えの破れ;
use crate::asset_generator::{アセット生成器の起動, 生成の指定, 生成器エラー};

pub trait ソースアセットの生成器を起こす係 {
    /// 生成器を組み立てさせ、組み上がった実行ファイルの中身を1つの値へ畳んで返す。生成の新しさの判定がこれを材料にする。
    fn 生成器を組み立てて実行ファイルの内容ハッシュを求める(
        &self,
    ) -> Result<内容ハッシュ, 生成物のソースアセットの取り揃えの破れ>;

    fn 検証用の世界一式を書き出す(&self, 理由: &str) -> Result<(), 生成器エラー>;

    fn 場所巡りの世界を種から書き出す(&self, 種: マップ生成の乱数の種, 理由: &str) -> Result<(), 生成器エラー>;
}

/// 生成器のexampleをcargoから起こす、実物の起こし方。
pub struct 生成器のexampleをcargoから起こす係;

impl ソースアセットの生成器を起こす係 for 生成器のexampleをcargoから起こす係 {
    fn 生成器を組み立てて実行ファイルの内容ハッシュを求める(
        &self,
    ) -> Result<内容ハッシュ, 生成物のソースアセットの取り揃えの破れ> {
        let 実行ファイル = ソースアセットの生成の指定()
            .生成器を組み立てて実行ファイルのパスを求める()
            .map_err(生成物のソースアセットの取り揃えの破れ::生成器が失敗した)?;
        内容ハッシュ::ファイルの中身から求める(&実行ファイル)
            .map_err(生成物のソースアセットの取り揃えの破れ::生成器の実行ファイルの中身を読めなかった)
    }

    fn 検証用の世界一式を書き出す(&self, 理由: &str) -> Result<(), 生成器エラー> {
        println!("[xtask] {理由}ため、検証用の世界一式を生成する");
        起こす(None)
    }

    fn 場所巡りの世界を種から書き出す(&self, 種: マップ生成の乱数の種, 理由: &str) -> Result<(), 生成器エラー> {
        println!("[xtask] {理由}ため、場所巡りの世界を種{}から生成する", 種.値());
        起こす(Some(種))
    }
}

/// 種を渡すか渡さないかだけが違う2つの起こし方を1つに束ねる。指定の枝はどちらも同じである。
fn 起こす(場所巡りの世界の種: Option<マップ生成の乱数の種>) -> Result<(), 生成器エラー> {
    アセット生成器の起動::始める(&ソースアセットの生成の指定を種つきで組む(場所巡りの世界の種))?.画面へ流したまま走らせて終わりを待つ()
}

/// 組み立てさせるだけの呼び出しが使う指定。どの生成器を組み立てるかだけが要るため、種は渡さない。
fn ソースアセットの生成の指定() -> 生成の指定<'static> {
    ソースアセットの生成の指定を種つきで組む(None)
}

fn ソースアセットの生成の指定を種つきで組む(
    場所巡りの世界の種: Option<マップ生成の乱数の種>
) -> 生成の指定<'static> {
    生成の指定::ソースアセットを生成する {
        場所巡りの世界の種,
        ソースルート: None,
        世界の広がり: None,
    }
}
