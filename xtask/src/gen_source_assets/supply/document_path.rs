//! 文書の相対パス: ソースルートからの相対で、追跡している文書1件を指す綴り。受け取るのは走査の起点と走査が返した
//! 絶対の綴り、返すのは相対の綴りである。
//!
//! 走査が返す絶対の綴りをそのまま持ち回らないのは、置き場の綴りが機械ごとに違い、写しを畳んだ値が文書の中身と
//! 無関係に変わるためである。人へ見せる行も置き場の綴りで長くなる。
//!
//! `ソースアセットの相対パス`を使わないのは、あちらが宣言の表を`const`のまま書くために`&'static str`しか持てず、
//! 走査が実行時に見つけた綴りを収められないためである。
//!
//! 見える範囲を`gen_source_assets`までにするのは、破れの型がこの型を枝の中に持ち、その破れが入口まで届くためである。
//! 型より広い範囲へ届く値を持たせると、受け取った側がその型を名指せない。

use std::path::{Path, PathBuf};

/// 綴りを見せるときに揃える区切りと、走査が返しうるもう一方の区切り。
const 揃える区切り: char = '/';
const 揃える前の区切り: char = '\\';

#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
#[repr(transparent)]
pub(in crate::gen_source_assets) struct 文書の相対パス(PathBuf);

impl 文書の相対パス {
    /// 前置きを落とせない綴りはそのまま収める。落とせないのは走査の起点の外を指す綴りだけであり、
    /// 落とせなかったことを黙って捨てると、その文書が写しから消えて食い違いを見逃す。
    pub(super) fn 走査の起点からの相対にする(走査の起点: &Path, 絶対の綴り: PathBuf) -> Self {
        match 絶対の綴り.strip_prefix(走査の起点) {
            Ok(相対) => Self(相対.to_path_buf()),
            Err(_) => Self(絶対の綴り),
        }
    }

    /// 人へ見せる綴りと、写しを畳むときの綴り。区切りを斜線へ揃えるのは、同じ文書の並びが実行環境によって
    /// 違う値へ畳まれないようにするためである。この揃え方は生成台帳の依存の畳みに倣う。
    pub(in crate::gen_source_assets) fn 綴りを見せる(&self) -> String {
        self.0.display().to_string().replace(揃える前の区切り, &揃える区切り.to_string())
    }
}
