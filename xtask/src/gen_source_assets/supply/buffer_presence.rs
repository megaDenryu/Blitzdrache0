//! 共有バッファが揃っているかを見る係。受け取るのは見る先のソースルートと相対パスの並び、
//! 返すのは欠けている相対パスの一覧と、生成の後にも欠けが残っていないかの判定である。
//!
//! 見る先を借りて持つのは、見る場所が揃える工程の持つソースルート1つで決まるためである。
//! 相対パスからソースの実パスを組むのはソースルートの側であり、ここは綴りを組み立てない。

use blitz_asset_compiler::{ソースアセットの相対パス, ソースルート};

use super::error::生成物のソースアセットの取り揃えの破れ;

pub(super) struct 共有バッファの揃いを見る係<'見る先>(&'見る先 ソースルート);

impl<'見る先> 共有バッファの揃いを見る係<'見る先> {
    pub(super) fn ソースルートの下を見る(ソースルート: &'見る先 ソースルート) -> Self {
        Self(ソースルート)
    }

    pub(super) fn 欠けている相対パス一覧(
        &self, 一覧: &[ソースアセットの相対パス]
    ) -> Vec<ソースアセットの相対パス> {
        一覧
            .iter()
            .copied()
            .filter(|相対パス| !self.0.宣言の相対パスが指すソース(*相対パス).is_file())
            .collect()
    }

    /// 生成の後にもう一度見るのは、生成器が書き出す名前とここが見る綴りが食い違ったときに、揃わないまま
    /// 毎回生成し続ける形へ落ちるためである。食い違いを黙って通さず、その場で落とす。
    pub(super) fn 生成の後の欠けを確かめる(
        &self,
        一覧: &[ソースアセットの相対パス],
    ) -> Result<(), 生成物のソースアセットの取り揃えの破れ> {
        let 揃わなかった相対パス一覧 = self.欠けている相対パス一覧(一覧);
        if 揃わなかった相対パス一覧.is_empty() {
            Ok(())
        } else {
            Err(生成物のソースアセットの取り揃えの破れ::生成しても共有バッファが揃わなかった {
                揃わなかった相対パス一覧,
            })
        }
    }
}
