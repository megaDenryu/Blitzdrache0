//! 試験の場面: 使い捨てのソースルートと、そこを見る揃える係を1つに束ねたもの。受け取るのは偽の生成器の振る舞い、
//! 返すのは揃える係と、起こされた回数と、置き場の片づけである。
//!
//! 場面を型にするのは、6つの検査がどれも「使い捨ての置き場を作り、乱数の種を書き、揃える係を組み、最後に片づける」
//! という同じ段取りを踏むためである。段取りを検査の側へ写すと、検査ごとに置き場の後始末が抜ける。

use std::cell::Cell;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU32, Ordering};

use blitz_asset_compiler::{
    アセット配置エラー, ソースルート, マップ生成の乱数の種, 場所巡りの世界のソースディレクトリ
};

use super::counting_launch::起こされた回数を数える偽の起こし係;
use super::fingerprint_ledger::生成の指紋の台帳;
use super::生成物のソースアセットを揃える係;

static 使い捨ての置き場の通し番号: AtomicU32 = AtomicU32::new(0);

/// 偽の生成器の実行ファイルの中身。2つの綴りが違うことだけが意味を持ち、指紋がその違いを拾う。
const 最初の生成器の中身: &str = "最初の生成器";
const 書き換えた生成器の中身: &str = "書き換えた生成器";

pub(super) struct 偽の生成器の振る舞い {
    実行ファイルの中身: &'static str,
    共有バッファを書くか: bool,
    板の文書へ書く中身: Option<&'static str>,
}

impl 偽の生成器の振る舞い {
    pub(super) fn 最初の生成器が共有バッファを書く() -> Self {
        Self::組む(最初の生成器の中身, true, None)
    }

    pub(super) fn 最初の生成器が共有バッファを書かない() -> Self {
        Self::組む(最初の生成器の中身, false, None)
    }

    pub(super) fn 書き換えた生成器が共有バッファを書く() -> Self {
        Self::組む(書き換えた生成器の中身, true, None)
    }

    pub(super) fn 最初の生成器が板の文書を書き直す(中身: &'static str) -> Self {
        Self::組む(最初の生成器の中身, true, Some(中身))
    }

    fn 組む(
        実行ファイルの中身: &'static str, 共有バッファを書くか: bool, 板の文書へ書く中身: Option<&'static str>
    ) -> Self {
        Self {
            実行ファイルの中身,
            共有バッファを書くか,
            板の文書へ書く中身,
        }
    }
}

pub(super) struct 使い捨ての場面 {
    パス: PathBuf,
    揃える係: 生成物のソースアセットを揃える係<起こされた回数を数える偽の起こし係>,
}

impl 使い捨ての場面 {
    /// 場所巡りの世界の乱数の種まで書いた使い捨てのソースルートを作る。種は決定性検収と同じものを使う。
    pub(super) fn 組み立てる(振る舞い: 偽の生成器の振る舞い) -> Result<Self, アセット配置エラー> {
        let 番号 = 使い捨ての置き場の通し番号.fetch_add(1, Ordering::Relaxed);
        let パス = std::env::temp_dir().join(format!("blitzdrache0-取り揃えの検査-{}-{番号}", std::process::id()));
        場所巡りの世界のソースディレクトリ::ソースルートの下に作る(&ソースルート::生成する(パス.clone()))?
            .生成に使った乱数の種を書き出す(crate::fox_tour_map_seed::決定性検収の乱数の種)?;
        Ok(Self::置き場を決めて組む(パス, 振る舞い))
    }

    /// 同じ置き場を別の振る舞いでもう一度使う。1周目の生成の結果と台帳をそのまま引き継いで2周目を見る。
    pub(super) fn 同じ置き場をもう一度使う(&self, 振る舞い: 偽の生成器の振る舞い) -> Self {
        Self::置き場を決めて組む(self.パス.clone(), 振る舞い)
    }

    fn 置き場を決めて組む(パス: PathBuf, 振る舞い: 偽の生成器の振る舞い) -> Self {
        let 揃える係 = 生成物のソースアセットを揃える係::ソースルートと起こし方を対にする(
            ソースルート::生成する(パス.clone()),
            起こされた回数を数える偽の起こし係 {
                ソースルートのパス: パス.clone(),
                共有バッファを書くか: 振る舞い.共有バッファを書くか,
                実行ファイルの中身: 振る舞い.実行ファイルの中身,
                板の文書へ書く中身: 振る舞い.板の文書へ書く中身,
                検証用の世界一式を起こした回数: Cell::new(0),
                場所巡りの世界を起こした回数: Cell::new(0),
            },
        );
        Self { パス, 揃える係 }
    }

    pub(super) fn 揃える係(&self) -> &生成物のソースアセットを揃える係<起こされた回数を数える偽の起こし係> {
        &self.揃える係
    }

    pub(super) fn ソースルートのパス(&self) -> &Path {
        &self.パス
    }

    pub(super) fn 一式と場所巡りを起こした回数(&self) -> (u32, u32) {
        self.揃える係.生成器を起こす係.一式と場所巡りを起こした回数()
    }

    /// 生成の入力だけを変える。指紋の材料のうち種の側が効いているかを見る検査が呼ぶ。
    pub(super) fn 場所巡りの世界の乱数の種を書き換える(
        &self, 種: マップ生成の乱数の種
    ) -> Result<(), アセット配置エラー> {
        場所巡りの世界のソースディレクトリ::ソースルートの下を開く(&ソースルート::生成する(self.パス.clone()))?
            .生成に使った乱数の種を書き出す(種)
    }

    /// 指紋の台帳を、在るが読めない綴りにする。読めない台帳を無い台帳と同じに扱うことを見る検査が呼ぶ。
    pub(super) fn 指紋の台帳の綴りを壊す(&self, 壊れた綴り: &str) -> std::io::Result<()> {
        let 台帳 = 生成の指紋の台帳::ソースルートの下を指す(&ソースルート::生成する(self.パス.clone()));
        std::fs::write(台帳.書き込み先のパス(), 壊れた綴り)
    }

    pub(super) fn 片づける(self) -> std::io::Result<()> {
        std::fs::remove_dir_all(&self.パス)
    }
}
