//! 生成の後に食い違いが残った場面の検査。共有バッファが揃わなかったとき、生成器が追跡している文書を書き直したとき、
//! 人が手で文書を書き換えたときの3つで、型付きエラーが食い違いを名指して落ちることを固定する。
//! 起こすかどうかの判定は`invariant_tests`が持ち、偽の起こし係は`counting_launch`が、場面の組み立ては`test_scene`が持つ。

#![allow(clippy::unwrap_used)]

use blitz_asset_compiler::ソースアセットの相対パス;

use super::buffer_group::検証用の世界一式の共有バッファ;
use super::counting_launch::起こされた回数を数える偽の起こし係;
use super::test_scene::{使い捨ての場面, 偽の生成器の振る舞い};
use super::生成物のソースアセットの取り揃えの破れ;

/// 追跡している文書の代わりに置く中身。書き直されたかどうかだけを見るため、glTFの体裁は問わない。
const 追跡していた文書の中身: &str = "追跡していた板の文書";
const 生成器が書き直した文書の中身: &str = "生成器が書き直した板の文書";
const 手で書き換えた文書の中身: &str = "人が手で書き換えた板の文書";

#[test]
fn 生成しても揃わなければ揃わなかった共有バッファを名指して落ちる() {
    let 場面 = 使い捨ての場面::組み立てる(偽の生成器の振る舞い::最初の生成器が共有バッファを書かない()).unwrap();
    let 結果 = 場面.揃える係().不足していれば生成して揃える();
    場面.片づける().unwrap();
    match 結果 {
        Err(生成物のソースアセットの取り揃えの破れ::生成しても共有バッファが揃わなかった {
            揃わなかった相対パス一覧,
        }) => assert_eq!(
            揃わなかった相対パス一覧.len(),
            検証用の世界一式の共有バッファ.len(),
            "揃わなかった共有バッファを全部は名指していない"
        ),
        ほか => panic!("揃わなかったことを型で言っていない: {ほか:?}"),
    }
}

#[test]
fn 追跡していた文書を生成器が書き直せば食い違いを名指して落ちる() {
    let 場面 = 使い捨ての場面::組み立てる(偽の生成器の振る舞い::最初の生成器が板の文書を書き直す(
        生成器が書き直した文書の中身,
    ))
    .unwrap();
    起こされた回数を数える偽の起こし係::文書か共有バッファを書く(
        場面.ソースルートのパス(),
        ソースアセットの相対パス::板,
        追跡していた文書の中身.as_bytes(),
    )
    .unwrap();
    let 結果 = 場面.揃える係().不足していれば生成して揃える();
    場面.片づける().unwrap();
    match 結果 {
        Err(生成物のソースアセットの取り揃えの破れ::追跡している文書が生成結果と食い違った {
            食い違ったパス一覧,
        }) => {
            assert_eq!(食い違ったパス一覧.len(), 1, "食い違った文書は板の文書1件のはずである");
        }
        ほか => panic!("文書の食い違いを型で言っていない: {ほか:?}"),
    }
}

#[test]
fn 追跡していた文書を手で書き換えれば共有バッファが揃っていても起きて食い違いで落ちる() {
    let 場面 = 使い捨ての場面::組み立てる(偽の生成器の振る舞い::最初の生成器が板の文書を書き直す(
        生成器が書き直した文書の中身,
    ))
    .unwrap();
    場面.揃える係().不足していれば生成して揃える().unwrap();
    起こされた回数を数える偽の起こし係::文書か共有バッファを書く(
        場面.ソースルートのパス(),
        ソースアセットの相対パス::板,
        手で書き換えた文書の中身.as_bytes(),
    )
    .unwrap();
    let 二周目 = 場面.同じ置き場をもう一度使う(偽の生成器の振る舞い::最初の生成器が板の文書を書き直す(
        生成器が書き直した文書の中身,
    ));
    let 結果 = 二周目.揃える係().不足していれば生成して揃える();
    let 回数 = 二周目.一式と場所巡りを起こした回数();
    場面.片づける().unwrap();
    assert_eq!(回数, (1, 1), "手で文書を書き換えたのに生成器を起こしていない");
    match 結果 {
        Err(生成物のソースアセットの取り揃えの破れ::追跡している文書が生成結果と食い違った {
            食い違ったパス一覧,
        }) => {
            assert_eq!(食い違ったパス一覧.len(), 1, "食い違った文書は板の文書1件のはずである");
        }
        ほか => panic!("手で書き換えた文書の食い違いを型で言っていない: {ほか:?}"),
    }
}
