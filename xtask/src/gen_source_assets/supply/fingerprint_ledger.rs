//! 生成の指紋の台帳: 最後に揃えたときの指紋を書いたファイルと、その本文の綴り。受け取るのはソースルート、
//! 返すのは記録された指紋の読み書きである。
//!
//! ソースルートの下へ置くのは、記録する対象がそのソースルートの下の生成物だからである。中身は機械ごとに違い
//! (生成器の実行ファイルの中身が入る)、ソースでも生成物そのものでもないため、Gitの無視の規則が拾う。
//!
//! 本文を「欄の名前 値」の行の並びにするのは、実行時形式の生成台帳の見出しと同じ綴り方にするためである。
//! 参照: `crates/blitz_asset_compiler/src/generation_ledger/ledger_text/build.rs`
//!
//! 生成台帳の型をそのまま使わないのは、あちらが世界のチャンクごとの記録を本体に持ち、見出しだけを切り出して
//! 使う口を外へ出していないためである。ここが要るのは見出しに当たる数値だけであり、チャンクの記録は1件も無い。

use std::path::PathBuf;

use blitz_asset_compiler::{ソースアセットの相対パス, ソースルート, マップ生成の乱数の種, 内容ハッシュ};

use super::error::生成物のソースアセットの取り揃えの破れ;
use super::fingerprint::生成の指紋;

/// 台帳の置き場。ソースルートの直下に置く。
const 台帳の相対パス: ソースアセットの相対パス = ソースアセットの相対パス::生成する("source_asset_fingerprint.txt");

const 生成器の実行ファイルの欄: &str = "生成器の実行ファイル";
const 種の欄: &str = "種";
const 追跡している文書の欄: &str = "追跡している文書";

pub(super) struct 生成の指紋の台帳 {
    パス: PathBuf,
}

impl 生成の指紋の台帳 {
    pub(super) fn ソースルートの下を指す(ソースルート: &ソースルート) -> Self {
        Self {
            パス: ソースルート.宣言の相対パスが指すソース(台帳の相対パス),
        }
    }

    /// 台帳が無いときと綴りが壊れているときは値なしを返す。どちらも記録を使えない点で同じであり、
    /// 値なしは生成器を起こす側へ倒れる。この倒し方は生成台帳の読み込みに倣う。
    pub(super) fn 記録された指紋を読む(&self) -> Option<生成の指紋> {
        本文から復元する(&std::fs::read_to_string(&self.パス).ok()?)
    }

    /// 台帳のファイルそのものの置き場。綴りが壊れている場面を作る検査がここへ書く。本番の経路は通らない。
    #[cfg(test)]
    pub(super) fn 書き込み先のパス(&self) -> &std::path::Path {
        &self.パス
    }

    pub(super) fn 指紋を書き出す(&self, 指紋: 生成の指紋) -> Result<(), 生成物のソースアセットの取り揃えの破れ> {
        std::fs::write(&self.パス, 本文を組み立てる(指紋)).map_err(|誤り| {
            生成物のソースアセットの取り揃えの破れ::指紋の台帳を書けなかった {
                パス: self.パス.clone(),
                誤り,
            }
        })
    }
}

fn 本文を組み立てる(指紋: 生成の指紋) -> String {
    format!(
        "{生成器の実行ファイルの欄} {}\n{種の欄} {}\n{追跡している文書の欄} {}\n",
        指紋.生成器の実行ファイルの内容ハッシュ().十六進の綴りを作る(),
        指紋.場所巡りの世界の種().値(),
        指紋.追跡している文書のダイジェスト().十六進の綴りを作る()
    )
}

fn 本文から復元する(本文: &str) -> Option<生成の指紋> {
    Some(生成の指紋::三つの材料から組む(
        内容ハッシュ::十六進の綴りから復元する(欄の値を探す(本文, 生成器の実行ファイルの欄)?)?,
        マップ生成の乱数の種::生成する(欄の値を探す(本文, 種の欄)?.parse().ok()?),
        内容ハッシュ::十六進の綴りから復元する(欄の値を探す(本文, 追跡している文書の欄)?)?,
    ))
}

fn 欄の値を探す<'本文>(本文: &'本文 str, 欄の名前: &str) -> Option<&'本文 str> {
    本文.lines().find_map(|行| 行.strip_prefix(欄の名前)).map(str::trim)
}
