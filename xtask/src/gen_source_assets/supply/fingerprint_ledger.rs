//! 生成の指紋の台帳: 最後に揃えたときの指紋を1行だけ書いたファイル。受け取るのはソースルート、
//! 返すのは記録された指紋の読み書きである。
//!
//! ソースルートの下へ置くのは、記録する対象がそのソースルートの下の生成物だからである。中身は機械ごとに違い
//! (生成器の実行ファイルの中身が入る)、ソースでも生成物そのものでもないため、Gitの無視の規則が拾う。
//! この置き方は実行時形式の生成台帳に倣う。参照: `crates/blitz_asset_compiler/src/generation_ledger/ledger.rs`

use std::path::PathBuf;

use blitz_asset_compiler::{ソースアセットの相対パス, ソースルート};

use super::error::生成物のソースアセットの取り揃えの破れ;
use super::fingerprint::生成の指紋;

/// 台帳の置き場。ソースルートの直下に置く。
const 台帳の相対パス: ソースアセットの相対パス = ソースアセットの相対パス::生成する("source_asset_fingerprint.txt");

pub(super) struct 生成の指紋の台帳 {
    パス: PathBuf,
}

impl 生成の指紋の台帳 {
    pub(super) fn ソースルートの下を指す(ソースルート: &ソースルート) -> Self {
        Self {
            パス: ソースルート.宣言の相対パスが指すソース(台帳の相対パス),
        }
    }

    /// 台帳が無いときと綴りが壊れているときは値なしを返す。どちらも記録を使えない点で同じであり、
    /// 値なしは生成器を起こす側へ倒れる。
    pub(super) fn 記録された指紋を読む(&self) -> Option<生成の指紋> {
        let 綴り = std::fs::read_to_string(&self.パス).ok()?;
        生成の指紋::十六進の綴りから復元する(綴り.trim())
    }

    pub(super) fn 指紋を書き出す(&self, 指紋: 生成の指紋) -> Result<(), 生成物のソースアセットの取り揃えの破れ> {
        std::fs::write(&self.パス, format!("{}\n", 指紋.十六進の綴りを作る())).map_err(|誤り| {
            生成物のソースアセットの取り揃えの破れ::指紋の台帳を書けなかった {
                パス: self.パス.clone(),
                誤り,
            }
        })
    }
}
