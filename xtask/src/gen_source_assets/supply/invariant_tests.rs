//! 揃える工程の不変条件の検査。生成器の起こし方を数える偽物へ差し替え、欠けているときだけ起こすことと、
//! 起こしても揃わなかったときに型付きエラーで落ちることを固定する。偽の起こし係は`counting_launch`が持つ。

#![allow(clippy::unwrap_used)]

use std::cell::Cell;
use std::path::PathBuf;
use std::sync::atomic::{AtomicU32, Ordering};

use blitz_asset_compiler::{ソースルート, 場所巡りの世界のソースディレクトリ};

use super::buffer_group::{場所巡りの世界の共有バッファ, 検証用の世界一式の共有バッファ};
use super::counting_launch::起こされた回数を数える偽の起こし係;
use super::{生成物のソースアセットの取り揃えの破れ, 生成物のソースアセットを揃える係};

static 使い捨ての置き場の通し番号: AtomicU32 = AtomicU32::new(0);

/// 場所巡りの世界の乱数の種まで書いた使い捨てのソースルートと、そこを見る揃える係。種は決定性検収と同じものを使う。
fn 使い捨てのソースルートと揃える係を作る(
    共有バッファを書くか: bool,
) -> (PathBuf, 生成物のソースアセットを揃える係<起こされた回数を数える偽の起こし係>) {
    let 番号 = 使い捨ての置き場の通し番号.fetch_add(1, Ordering::Relaxed);
    let パス = std::env::temp_dir().join(format!("blitzdrache0-取り揃えの検査-{}-{番号}", std::process::id()));
    let ソースルートの値 = ソースルート::生成する(パス.clone());
    場所巡りの世界のソースディレクトリ::ソースルートの下に作る(&ソースルートの値)
        .unwrap()
        .生成に使った乱数の種を書き出す(crate::fox_tour_map_seed::決定性検収の乱数の種)
        .unwrap();
    let 揃える係 = 生成物のソースアセットを揃える係::ソースルートと起こし方を対にする(
        ソースルートの値,
        起こされた回数を数える偽の起こし係 {
            ソースルートのパス: パス.clone(),
            共有バッファを書くか,
            検証用の世界一式を起こした回数: Cell::new(0),
            場所巡りの世界を起こした回数: Cell::new(0),
        },
    );
    (パス, 揃える係)
}

#[test]
fn 共有バッファが欠けているときに生成器を起こす() {
    let (パス, 揃える係) = 使い捨てのソースルートと揃える係を作る(true);
    let 結果 = 揃える係.不足していれば生成して揃える();
    let 回数 = 揃える係.生成器を起こす係.一式と場所巡りを起こした回数();
    std::fs::remove_dir_all(&パス).unwrap();
    assert!(結果.is_ok(), "揃えられなかった: {:?}", 結果.err());
    assert_eq!(回数, (1, 1), "欠けているのに生成器を起こしていない");
}

#[test]
fn 共有バッファが揃っているときに生成器を起こさない() {
    let (パス, 揃える係) = 使い捨てのソースルートと揃える係を作る(false);
    起こされた回数を数える偽の起こし係::空の共有バッファを置く(&パス, &検証用の世界一式の共有バッファ).unwrap();
    起こされた回数を数える偽の起こし係::空の共有バッファを置く(&パス, &場所巡りの世界の共有バッファ).unwrap();
    let 結果 = 揃える係.不足していれば生成して揃える();
    let 回数 = 揃える係.生成器を起こす係.一式と場所巡りを起こした回数();
    std::fs::remove_dir_all(&パス).unwrap();
    assert!(結果.is_ok(), "揃っているのに落ちた: {:?}", 結果.err());
    assert_eq!(回数, (0, 0), "揃っているのに生成器を起こした");
}

#[test]
fn 生成しても揃わなければ揃わなかった綴りを名指して落ちる() {
    let (パス, 揃える係) = 使い捨てのソースルートと揃える係を作る(false);
    let 結果 = 揃える係.不足していれば生成して揃える();
    std::fs::remove_dir_all(&パス).unwrap();
    match 結果 {
        Err(生成物のソースアセットの取り揃えの破れ::生成しても共有バッファが揃わなかった {
            揃わなかった相対パス一覧,
        }) => {
            assert_eq!(
                揃わなかった相対パス一覧.len(),
                検証用の世界一式の共有バッファ.len(),
                "揃わなかった共有バッファを全部は名指していない"
            );
        }
        ほか => panic!("揃わなかったことを型で言っていない: {ほか:?}"),
    }
}
