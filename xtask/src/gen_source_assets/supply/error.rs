//! 生成物のソースアセットを揃える工程が返す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! 文面が実行すべき命令を名指すのは、揃わなかったときに別の道へ倒さず人の手へ返すためである。
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。

use std::path::PathBuf;

use blitz_asset_compiler::{アセット配置エラー, ソースアセットの相対パス, 生成台帳エラー};

use super::document_path::文書の相対パス;
use crate::asset_generator::生成器エラー;
use crate::file_scan::ファイル走査の破れ;

#[derive(Debug)]
pub enum 生成物のソースアセットの取り揃えの破れ {
    生成器が失敗した(生成器エラー),
    場所巡りの世界の乱数の種を読めなかった(アセット配置エラー),
    生成しても共有バッファが揃わなかった {
        揃わなかった相対パス一覧: Vec<ソースアセットの相対パス>,
    },
    生成器の実行ファイルの中身を読めなかった(生成台帳エラー),
    指紋の台帳を書けなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    文書の走査に失敗した(ファイル走査の破れ),
    文書の中身を読めなかった(生成台帳エラー),
    追跡している文書が生成結果と食い違った {
        食い違ったパス一覧: Vec<文書の相対パス>,
    },
}

impl std::error::Error for 生成物のソースアセットの取り揃えの破れ {}

impl std::fmt::Display for 生成物のソースアセットの取り揃えの破れ {
    fn fmt(&self, 書き手: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::生成器が失敗した(誤り) => {
                write!(書き手, "生成物のソースアセットを生成できなかった: {誤り}")
            }
            Self::場所巡りの世界の乱数の種を読めなかった(誤り) => write!(
                書き手,
                "場所巡りの世界を生成した乱数の種を読めなかった({誤り})。cargo xtask gen-game-map --seed <32ビットの非負整数> でこの世界を作り直す"
            ),
            Self::生成しても共有バッファが揃わなかった {
                揃わなかった相対パス一覧
            } => write!(
                書き手,
                "生成器を走らせても共有バッファが揃わなかった({})。生成器が書き出す名前と、揃っているかを見る側が持つ綴りが食い違っている",
                揃わなかった相対パス一覧
                    .iter()
                    .map(|相対パス| 相対パス.綴りを見せる())
                    .collect::<Vec<_>>()
                    .join("、")
            ),
            Self::生成器の実行ファイルの中身を読めなかった(誤り) => {
                write!(書き手, "生成器の実行ファイルの中身を読めなかった: {誤り}")
            }
            Self::指紋の台帳を書けなかった { パス, 誤り } => {
                write!(書き手, "生成の指紋の台帳({})を書けなかった: {誤り}", パス.display())
            }
            Self::文書の走査に失敗した(誤り) => write!(書き手, "追跡している文書を走査できなかった: {誤り}"),
            Self::文書の中身を読めなかった(誤り) => write!(書き手, "追跡している文書の中身を読めなかった: {誤り}"),
            Self::追跡している文書が生成結果と食い違った { 食い違ったパス一覧 } => write!(
                書き手,
                "生成器が書き直した文書が、追跡していた中身と食い違った({})。正本は生成器のコードと入力であり、追跡している文書は生成のスナップショットである。書き直された文書をコミットする",
                食い違ったパス一覧.iter().map(文書の相対パス::綴りを見せる).collect::<Vec<_>>().join("、")
            ),
        }
    }
}
