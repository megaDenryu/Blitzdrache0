//! 生成物のソースアセットを揃える工程。glTFの文書が`uri`で指す共有バッファ(`.bin`)はどれも生成物であり、
//! Gitの追跡に入っていない。cloneした直後の作業ツリーにはこれが1件も無いため、共有バッファを読む入口は
//! 読む前にここを通る。
//!
//! 揃っているかを見てから起こすのは、生成が同じ入力から同じ出力を書く決定的なものだからである。揃っているのに
//! 毎回起こすと、共有バッファを読む入口すべてに生成器の実行時間が乗る。
//!
//! ソースルートと生成器の起こし方を対で持つのは、見る場所と書く場所が食い違うと「生成しても揃わない」形になる
//! ためである。実物の起こし方は既定のソースルート(`assets`)へ書くため、`既定のソースルートで作る`だけがその対を作る。
//! 欠けの数え上げは`buffer_group`が、起こし方は`generator_launch`が、破れの型は`error`が持つ。

mod buffer_group;
#[cfg(test)]
mod counting_launch;
mod error;
mod generator_launch;
#[cfg(test)]
mod invariant_tests;

use blitz_asset_compiler::{ソースアセットの相対パス, ソースルート, 場所巡りの世界のソースディレクトリ};

pub use error::生成物のソースアセットの取り揃えの破れ;
use generator_launch::{ソースアセットの生成器を起こす係, 生成器のexampleをcargoから起こす係};

pub struct 生成物のソースアセットを揃える係<起こし方> {
    ソースルート: ソースルート,
    生成器を起こす係: 起こし方,
}

impl 生成物のソースアセットを揃える係<生成器のexampleをcargoから起こす係> {
    /// リポジトリの既定のソースルートと、実物の生成器の起こし方を対にする。入口はこの口だけを通る。
    pub fn 既定のソースルートで作る() -> Self {
        Self::ソースルートと起こし方を対にする(
            ソースルート::生成する(crate::compile_assets::ソースルート().to_path_buf()),
            生成器のexampleをcargoから起こす係,
        )
    }
}

impl<起こし方: ソースアセットの生成器を起こす係> 生成物のソースアセットを揃える係<起こし方> {
    pub fn ソースルートと起こし方を対にする(ソースルート: ソースルート, 生成器を起こす係: 起こし方) -> Self {
        Self {
            ソースルート,
            生成器を起こす係,
        }
    }

    pub fn 不足していれば生成して揃える(&self) -> Result<(), 生成物のソースアセットの取り揃えの破れ> {
        self.検証用の世界一式の共有バッファを揃える()?;
        self.場所巡りの世界の共有バッファを揃える()
    }

    fn 検証用の世界一式の共有バッファを揃える(&self) -> Result<(), 生成物のソースアセットの取り揃えの破れ> {
        if self.欠けている相対パス一覧(&buffer_group::検証用の世界一式の共有バッファ).is_empty() {
            return Ok(());
        }
        self.生成器を起こす係
            .検証用の世界一式を書き出す()
            .map_err(生成物のソースアセットの取り揃えの破れ::生成器が失敗した)?;
        self.生成の後の欠けを確かめる(&buffer_group::検証用の世界一式の共有バッファ)
    }

    /// 種を既定へ倒さず、この世界を生成したときの種を書いたファイルから読む。既定へ倒すと、追跡している
    /// 高さ格子と目印の柱が別の世界のものへ黙って入れ替わる。
    fn 場所巡りの世界の共有バッファを揃える(&self) -> Result<(), 生成物のソースアセットの取り揃えの破れ> {
        if self.欠けている相対パス一覧(&buffer_group::場所巡りの世界の共有バッファ).is_empty() {
            return Ok(());
        }
        let 種 = 場所巡りの世界のソースディレクトリ::ソースルートの下を開く(&self.ソースルート)
            .and_then(|置き場| 置き場.生成に使った乱数の種を読む())
            .map_err(生成物のソースアセットの取り揃えの破れ::場所巡りの世界の乱数の種を読めなかった)?;
        self.生成器を起こす係
            .場所巡りの世界を種から書き出す(種)
            .map_err(生成物のソースアセットの取り揃えの破れ::生成器が失敗した)?;
        self.生成の後の欠けを確かめる(&buffer_group::場所巡りの世界の共有バッファ)
    }

    /// 生成の後にもう一度見るのは、生成器が書き出す名前とここが見る綴りが食い違ったときに、揃わないまま
    /// 毎回生成し続ける形へ落ちるためである。食い違いを黙って通さず、その場で落とす。
    fn 生成の後の欠けを確かめる(
        &self,
        一覧: &[ソースアセットの相対パス],
    ) -> Result<(), 生成物のソースアセットの取り揃えの破れ> {
        let 揃わなかった相対パス一覧 = self.欠けている相対パス一覧(一覧);
        if 揃わなかった相対パス一覧.is_empty() {
            Ok(())
        } else {
            Err(生成物のソースアセットの取り揃えの破れ::生成しても共有バッファが揃わなかった {
                揃わなかった相対パス一覧,
            })
        }
    }

    fn 欠けている相対パス一覧(&self, 一覧: &[ソースアセットの相対パス]) -> Vec<ソースアセットの相対パス> {
        一覧
            .iter()
            .copied()
            .filter(|相対パス| !self.ソースルート.宣言の相対パスが指すソース(*相対パス).is_file())
            .collect()
    }
}
