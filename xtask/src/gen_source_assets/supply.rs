use blitz_asset_compiler::{ソースルート, マップ生成の乱数の種, 場所巡りの世界のソースディレクトリ};

use buffer_presence::{共有バッファの揃いを見る係, 群の生成器を起こす理由};
use document_snapshot::生成の直前の文書の写し;
pub use error::生成物のソースアセットの取り揃えの破れ;
use fingerprint::生成の指紋;
use fingerprint_ledger::生成の指紋の台帳;
use generator_launch::{ソースアセットの生成器を起こす係, 生成器のexampleをcargoから起こす係};

pub struct 生成物のソースアセットを揃える係<起こし方> {
    ソースルート: ソースルート,
    生成器を起こす係: 起こし方,
}

impl 生成物のソースアセットを揃える係<生成器のexampleをcargoから起こす係> {
    /// リポジトリの既定のソースルートと、実物の生成器の起こし方を対にする。入口はこの口だけを通る。
    pub fn 既定のソースルートで作る() -> Self {
        Self::ソースルートと起こし方を対にする(
            ソースルート::生成する(crate::compile_assets::ソースルート().to_path_buf()),
            生成器のexampleをcargoから起こす係,
        )
    }
}

impl<起こし方: ソースアセットの生成器を起こす係> 生成物のソースアセットを揃える係<起こし方> {
    pub fn ソースルートと起こし方を対にする(ソースルート: ソースルート, 生成器を起こす係: 起こし方) -> Self {
        Self {
            ソースルート,
            生成器を起こす係,
        }
    }

    /// 新しくないか、共有バッファが欠けているときだけ生成器を起こす。起こしたなら、揃ったことと、追跡している
    /// 文書が生成結果と一致することを確かめてから、生成の後の状態の指紋を台帳へ書く。
    ///
    /// 台帳へ書く指紋が生成の後の文書を材料に取るのは、生成器が文書も書き直すためである。生成の前の状態で書くと、
    /// 次の実行が「文書が変わった」と読んで毎回起こすことになる。
    pub fn 不足していれば生成して揃える(&self) -> Result<(), 生成物のソースアセットの取り揃えの破れ> {
        let 種 = self.場所巡りの世界の乱数の種を読む()?;
        let 文書の写し = 生成の直前の文書の写し::ソースルートの下でいま撮る(&self.ソースルート)?;
        let 指紋 = 生成の指紋::三つの材料から組む(
            self.生成器を起こす係.生成器を組み立てて実行ファイルの内容ハッシュを求める()?,
            種,
            文書の写し.畳んだ内容ハッシュ(),
        );
        let 台帳 = 生成の指紋の台帳::ソースルートの下を指す(&self.ソースルート);
        let 新しさ = 指紋.記録と見比べる(台帳.記録された指紋を読む());
        let 揃いを見る係 = 共有バッファの揃いを見る係::ソースルートの下を見る(&self.ソースルート);
        let 一式の理由 = 揃いを見る係.群の生成器を起こす理由(新しさ, &buffer_group::検証用の世界一式の共有バッファ);
        let 場所巡りの理由 = 揃いを見る係.群の生成器を起こす理由(新しさ, &buffer_group::場所巡りの世界の共有バッファ);
        if 一式の理由.is_none() && 場所巡りの理由.is_none() {
            return Ok(());
        }
        self.群を起こす(一式の理由, 場所巡りの理由, 種)?;
        揃いを見る係.生成の後の欠けを確かめる(&buffer_group::検証用の世界一式の共有バッファ)?;
        揃いを見る係.生成の後の欠けを確かめる(&buffer_group::場所巡りの世界の共有バッファ)?;
        let 生成の後の文書 = 文書の写し.生成の後の食い違いを確かめる(&self.ソースルート)?;
        台帳.指紋を書き出す(指紋.文書のダイジェストを差し替える(生成の後の文書))
    }

    fn 群を起こす(
        &self,
        一式の理由: Option<群の生成器を起こす理由>,
        場所巡りの理由: Option<群の生成器を起こす理由>,
        種: マップ生成の乱数の種,
    ) -> Result<(), 生成物のソースアセットの取り揃えの破れ> {
        if let Some(理由) = 一式の理由 {
            self.生成器を起こす係
                .検証用の世界一式を書き出す(理由.説明())
                .map_err(生成物のソースアセットの取り揃えの破れ::生成器が失敗した)?;
        }
        if let Some(理由) = 場所巡りの理由 {
            self.生成器を起こす係
                .場所巡りの世界を種から書き出す(種, 理由.説明())
                .map_err(生成物のソースアセットの取り揃えの破れ::生成器が失敗した)?;
        }
        Ok(())
    }

    /// 種を既定へ倒さず、この世界を生成したときの種を書いたファイルから読む。既定へ倒すと、追跡している
    /// 高さ格子と目印の柱が別の世界のものへ黙って入れ替わる。
    fn 場所巡りの世界の乱数の種を読む(
        &self,
    ) -> Result<マップ生成の乱数の種, 生成物のソースアセットの取り揃えの破れ> {
        場所巡りの世界のソースディレクトリ::ソースルートの下を開く(&self.ソースルート)
            .and_then(|置き場| 置き場.生成に使った乱数の種を読む())
            .map_err(生成物のソースアセットの取り揃えの破れ::場所巡りの世界の乱数の種を読めなかった)
    }
}
