//! 生成物のソースアセットを揃える工程。glTFの文書が`uri`で指す共有バッファ(`.bin`)はどれも生成物であり、
//! Gitの追跡に入っていない。cloneした直後の作業ツリーにはこれが1件も無いため、共有バッファを読む入口は
//! 読む前にここを通る。
//!
//! 見るのは在るかどうかではなく、いまの生成器といまの入力に対して新しいかどうかである。在るかどうかだけを見ると、
//! 生成器のコードや生成規則を変えた後も古い共有バッファを読み続け、追跡に入っていないその食い違いは差分に現れない。
//! 判定の材料は`fingerprint`が畳み、最後に揃えたときの値は`fingerprint_ledger`が持つ。
//!
//! 正本は生成器のコードと生成の入力であり、追跡している文書(`.gltf`)は追跡された生成のスナップショットである。
//! 生成の後に文書の中身が変わったなら、正本が変わったのにスナップショットが古いままである。`document_snapshot`が
//! それを見て落とす。
//!
//! ソースルートと生成器の起こし方を対で持つのは、見る場所と書く場所が食い違うと「生成しても揃わない」形になる
//! ためである。実物の起こし方は既定のソースルート(`assets`)へ書くため、`既定のソースルートで作る`だけがその対を作る。
//! 欠けの数え上げは`buffer_group`が、揃っているかを見るのは`buffer_presence`が、起こし方は`generator_launch`が、
//! 破れの型は`error`が持つ。

