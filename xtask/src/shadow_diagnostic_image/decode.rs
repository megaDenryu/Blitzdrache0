//! 影の欠落計器の1画素の色から、影可視度と受光距離帯を戻す工程。受け取るのは8ビットの3成分、
//! 返すのは幾何の印が立っていれば診断画素、立っていなければ無しである。
//!
//! 符号化は`shaders/pixel_diagnostic.slang`の`shadowLossDiagnosticColor`が作る。赤が影可視度、緑が受光距離帯、
//! 青が幾何の印である。出力は交換チェーンのsRGB符号化を通るため、ここで同じ伝達関数の逆をかけて線形へ戻す。

#[cfg(test)]
mod band_tests;

use super::{帯数, 診断画素};

/// 受光距離帯の数を実数で持ったもの。帯の境界を割り算で作るために持ち、上の`帯数`と同じ値でなければならない。
/// 2つが食い違うと帯番号の読み戻しがずれるため、下のテストが往復で固定する。
const 帯数の実数: f64 = 16.0;
/// 幾何の印とみなす青の下限。背景は既定のクリア色(青成分0.12)であり、この下限に遠く届かない。
const 幾何の印の下限: u8 = 250;

pub(super) fn 判別する(色: [u8; 3]) -> Option<診断画素> {
    let [赤, 緑, 青] = 色;
    if 青 < 幾何の印の下限 {
        return None;
    }
    Some(診断画素 {
        影可視度: 線形へ戻す(赤),
        受光距離帯: 帯番号を戻す(緑),
    })
}

/// 緑の値から帯番号を戻す。シェーダーは(帯+1)/帯数を載せるため、隣り合う帯の中点と順に比べれば丸めの縮小変換を持ち込まずに戻せる。
fn 帯番号を戻す(緑: u8) -> usize {
    let 値 = 線形へ戻す(緑);
    let 刻み = 1.0 / 帯数の実数;
    let mut 番号 = 0;
    let mut 中点 = 刻み * 1.5;
    while 番号 + 1 < 帯数 && 値 >= 中点 {
        番号 += 1;
        中点 += 刻み;
    }
    番号
}

/// sRGBの伝達関数の逆。交換チェーンが書き出しで掛けた符号化をここで打ち消す。
fn 線形へ戻す(値: u8) -> f64 {
    let 符号化 = f64::from(値) / 255.0;
    if 符号化 <= 0.040_448_236 {
        return 符号化 / 12.92;
    }
    ((符号化 + 0.055) / 1.055).powf(2.4)
}
