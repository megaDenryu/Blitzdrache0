//! blitz_appが出した動きベクトルの要約行を数の並びへ直す工程。受け取るのは終了時報告、返すのは1行ぶんの観測である。
//!
//! 行が1本も無いことを失敗にするのは、読み戻しが1度も走らなかった実行を「静止で零だった」と読み替えないためである。
//! 見送りの行も同じ理由で失敗にする。
//!
//! 見送りの綴りを行の原文から探すのは、見送りの行が他の項目を1つも持たないためである。鍵で読もうとすると、
//! 「読み戻しが見送られた」でなく「全画素の鍵が無い」という別の理由で落ちる。

use crate::acceptance::{判定の名前, 報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

const 行の見出し: 報告の見出し = 報告の見出し::定数から生成する("[motion-vector]");
/// 読み戻しが成立しなかった実行の行に現れる綴り。正本は`crates/blitz_app/src/reports/motion_vector.rs`である。
const 読み戻しの見送りの綴り: &str = "見送った";
/// この報告の行は読点で区切り、鍵に数がそのまま続く。
const 値の結ばれ方: 鍵に値が結ばれる形 = 鍵に値が結ばれる形::この綴りに続く数字の並びが値である;

/// 1条件ぶんの観測。どの条件で採ったかは呼び出し元が持つため、この型は数だけを運ぶ。
pub(super) struct 観測 {
    pub(super) 全画素数: u64,
    pub(super) 超えた画素数: u64, // 大きさが1画素ぶんの正規化装置座標の幅を超えた画素の数
    pub(super) 非有限画素数: u64, // 2成分のどちらかが非数か無限大である画素の数。動きベクトルを読む側はこの値を扱えないため0でなければならない
    pub(super) 最大の大きさ: f32, // 有限の画素だけで採った大きさの最大
    pub(super) 一画素の幅: f32,
}

pub(super) fn 取り出す(報告: &終了時報告) -> Result<観測, 検収エラー> {
    let 行 = 報告.見出しの1行(&行の見出し)?;
    見送りの判定名(&行).零件であることを課す(u64::from(行.原文().contains(読み戻しの見送りの綴り)))?;
    Ok(観測 {
        全画素数: 数を読む(&行, "全画素")?,
        一画素の幅: 小数を読む(&行, "1画素の幅")?,
        超えた画素数: 数を読む(&行, "を超えた画素")?,
        非有限画素数: 数を読む(&行, "非有限画素")?,
        最大の大きさ: 小数を読む(&行, "大きさの最大")?,
    })
}

fn 数を読む(行: &報告の行, 鍵の綴り: &str) -> Result<u64, 検収エラー> {
    行.鍵に結ばれた数(&鍵を組む(鍵の綴り), 値の結ばれ方)
}

fn 小数を読む(行: &報告の行, 鍵の綴り: &str) -> Result<f32, 検収エラー> {
    行.鍵に結ばれた数(&鍵を組む(鍵の綴り), 値の結ばれ方)
}

fn 鍵を組む(綴り: &str) -> 報告の行の鍵 {
    報告の行の鍵::組み立てた綴りから生成する(綴り.to_string())
}

/// 見送りの行そのものを綴りへ入れるのは、blitz_appが見送った理由をその行に書いているためである。
fn 見送りの判定名(行: &報告の行) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("動きベクトルの要約行の読み戻しの見送り(行「{}」)", 行.原文()))
}
