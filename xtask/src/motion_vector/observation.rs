//! blitz_appが出した動きベクトルの要約行を数の並びへ直す工程。受け取るのは標準出力と条件、返すのは1行ぶんの観測である。
//!
//! 行が1本も無いことを失敗にするのは、読み戻しが1度も走らなかった実行を「静止で零だった」と読み替えないためである。
//! 見送りの行も同じ理由で失敗にする。

use super::condition::条件;

const 行の見出し: &str = "[motion-vector]";

/// 1条件ぶんの観測。どの条件で採ったかは呼び出し元が持つため、この型は数だけを運ぶ。
pub(super) struct 観測 {
    pub(super) 全画素数: u64,
    /// 大きさが1画素ぶんの正規化装置座標の幅を超えた画素の数。
    pub(super) 超えた画素数: u64,
    /// 2成分のどちらかが非数か無限大である画素の数。動きベクトルを読む側はこの値を扱えないため0でなければならない。
    pub(super) 非有限画素数: u64,
    /// 有限の画素だけで採った大きさの最大。
    pub(super) 最大の大きさ: f32,
    pub(super) 一画素の幅: f32,
}

pub(super) fn 取り出す(標準出力: &str, 条件: 条件) -> Result<観測, String> {
    let 行 = 標準出力
        .lines()
        .find(|行| 行.contains(行の見出し))
        .ok_or_else(|| format!("{}の出力に動きベクトルの要約行が無い", 条件.名前()))?;
    if 行.contains("見送った") {
        return Err(format!("{}で読み戻しが見送られた: {行}", 条件.名前()));
    }
    Ok(観測 {
        全画素数: 数を読む(行, "全画素", 条件)?,
        一画素の幅: 小数を読む(行, "1画素の幅", 条件)?,
        超えた画素数: 数を読む(行, "を超えた画素", 条件)?,
        非有限画素数: 数を読む(行, "非有限画素", 条件)?,
        最大の大きさ: 小数を読む(行, "大きさの最大", 条件)?,
    })
}

/// 見出しの語に続く数字の並びを読む。行の並びが変わっても語で拾えるため、位置に依存しない。
fn 数を読む(行: &str, 語: &str, 条件: 条件) -> Result<u64, String> {
    語に続く字面(行, 語, 条件)?
        .parse()
        .map_err(|誤り| format!("{}の{語}を整数として読めない: {誤り}", 条件.名前()))
}

fn 小数を読む(行: &str, 語: &str, 条件: 条件) -> Result<f32, String> {
    語に続く字面(行, 語, 条件)?
        .parse()
        .map_err(|誤り| format!("{}の{語}を小数として読めない: {誤り}", 条件.名前()))
}

fn 語に続く字面(行: &str, 語: &str, 条件: 条件) -> Result<String, String> {
    let 残り = 行
        .split_once(語)
        .map(|(_, 後ろ)| 後ろ)
        .ok_or_else(|| format!("{}の要約行に{語}が無い: {行}", 条件.名前()))?;
    let 字面: String = 残り.chars().take_while(|文字| 文字.is_ascii_digit() || *文字 == '.').collect();
    if 字面.is_empty() {
        return Err(format!("{}の{語}に続く数が読めない: {行}", 条件.名前()));
    }
    Ok(字面)
}
