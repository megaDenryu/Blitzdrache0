//! この入口が持つ機械判定。受け取るのは2条件の観測、返すのは合否である。
//!
//! 判定を段取りから分けるのは、「この入口が何を落とすか」を1箇所で読めるようにするためである。
//! 判定に使う量を1画素ぶんの正規化装置座標の幅に採るのは、その量が画面の寸法から一意に決まり、
//! 制定を要る閾値でないためである。

use super::condition::条件;
use super::observation::観測;
use crate::acceptance::{判定の名前, 判定の破れ};

const 非有限の画素: 判定の名前 = 判定の名前::定数から生成する("動きベクトルの非数か無限大の画素");
const 二条件の画素数: 判定の名前 = 判定の名前::定数から生成する("静止と移動の2条件の画素数");

pub(super) fn 判定する(静止: &観測, 移動: &観測) -> Result<(), 判定の破れ> {
    静止の判定名(静止).零件であることを課す(静止.超えた画素数)?;
    if 移動.超えた画素数 == 0 {
        return Err(移動の判定名(移動).あるはずのものが無い破れ());
    }
    for 観測 in [静止, 移動] {
        非有限の画素.零件であることを課す(観測.非有限画素数)?;
    }
    二条件の画素数.一致を課す(静止.全画素数, 移動.全画素数)
}

/// 1画素の幅と最大の大きさを綴りへ入れるのは、件数で課す判定が比べた実数を文面へ出せないためである。
fn 静止の判定名(静止: &観測) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "「{}」実行で1画素の幅{:.6}を超えた画素(最大{:.6})",
        条件::カメラを止める.名前(),
        静止.一画素の幅,
        静止.最大の大きさ
    ))
}

fn 移動の判定名(移動: &観測) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "「{}」実行で1画素の幅{:.6}を超えた画素(最大{:.6}。1つも無いなら動きベクトルが書かれていない)",
        条件::カメラを動かす.名前(),
        移動.一画素の幅,
        移動.最大の大きさ
    ))
}
