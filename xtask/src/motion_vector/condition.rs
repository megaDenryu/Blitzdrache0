//! 動きベクトルの観測を採る2つの条件。持つのは条件の別と、その表示名だけである。
//!
//! 2つを対で採るのは、片方だけでは「書かれていない」と「動いていないから零である」を区別できないためである。
//! カメラを止めた実行で1画素も動かず、動かした実行で画素が動くという対比が、書き手が実際に働いていることの
//! 反証になる。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 条件 {
    カメラを止める, // 1度も動かさない実行。静止した世界では動きベクトルが1画素の幅を超えない
    カメラを動かす, // 1フレームおきに奥へ動かす実行。最終フレームは直前のフレームから既知量だけ動いている
}

impl 条件 {
    pub(super) const fn 名前(self) -> &'static str {
        match self {
            Self::カメラを止める => "カメラを止める",
            Self::カメラを動かす => "カメラを動かす",
        }
    }

    /// 失敗の文面がこの実行を名指すための綴り。ファイル名にもなるためASCIIで保つ。
    pub(super) const fn 実行名の綴り(self) -> &'static str {
        match self {
            Self::カメラを止める => "camera_still",
            Self::カメラを動かす => "camera_moving",
        }
    }
}
