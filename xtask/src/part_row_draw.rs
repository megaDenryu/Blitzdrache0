//! 部品で組んだ並びを焼いて実機で描く検収の入口2つ。家の並びは段4の実証を、木の並びは組み上がった木の姿の目視を担当する。
//!
//! 2つを1つのモジュールへ収めるのは、焼く工程が同じ1本の報告の行を出し、その読み取りを共有するためである
//! (`tally_line`)。読み取りを別々に持つと、綴りの写しが2つに分かれ、片方だけ直した食い違いが起きる。
//!
//! 見るものは違う。家の並びは10軒と100軒を突き合わせて発行数が件数に依らないことを機械で確かめ、
//! 木の並びは1本の姿を人が判定できる大きさで写す。判定の中身はそれぞれの側が持つ。

mod house_row;
mod tally_line;
mod tree_row;

use std::process::ExitCode;

pub fn 家の並びを検収する() -> ExitCode {
    house_row::実行する()
}

pub fn 木の並びを撮影する() -> ExitCode {
    tree_row::実行する()
}
