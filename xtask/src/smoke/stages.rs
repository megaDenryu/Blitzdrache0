//! スモーク検証の各ステージを既定の順序で実行する。

use std::path::Path;

use crate::fetch_assets::{フォックスの取得対象, ヘルメットの取得対象};

use super::launch_setting::起動設定;
use super::run_stage::必須ステージを実行する;
use super::stage_catalog::{
    キツネのシーン, ヘルメットのシーン, 四角形フレーム数, 影のシーン, 板のシーン, 短時間フレーム数
};
use crate::acceptance::検収の実行名;

pub(super) fn すべてを実行する(シェーダー: &Path, アセット: &Path) -> bool {
    四角形(シェーダー, アセット)
        && ヘルメット(シェーダー)
        && 粒子(シェーダー, アセット)
        && 開発ui(シェーダー, アセット)
        && シャドウ(シェーダー, アセット)
        && フォックス(シェーダー)
        && 布(シェーダー, アセット)
        && ポスト有効リサイズ(シェーダー, アセット)
}

fn 四角形(シェーダー: &Path, アセット: &Path) -> bool {
    let 設定 = 起動設定::生成する(四角形フレーム数, シェーダー, Some(アセット), 板のシーン)
        .照明なし()
        .ポストなし();
    必須ステージを実行する(検収の実行名::定数から生成する("quad"), 設定)
}

fn ヘルメット(シェーダー: &Path) -> bool {
    if !ヘルメットの取得対象.取得済みか() {
        println!("[xtask] helmetアセット未取得のためhelmetステージをスキップした(cargo xtask fetch-assetsで取得可)");
        return true;
    }
    必須ステージを実行する(
        検収の実行名::定数から生成する("helmet"),
        起動設定::生成する(短時間フレーム数, シェーダー, None, ヘルメットのシーン),
    )
}

fn 粒子(シェーダー: &Path, アセット: &Path) -> bool {
    let 設定 = 起動設定::生成する(短時間フレーム数, シェーダー, Some(アセット), 板のシーン)
        .照明なし()
        .粒子あり()
        .ポストなし();
    必須ステージを実行する(検収の実行名::定数から生成する("particles"), 設定)
}

fn 開発ui(シェーダー: &Path, アセット: &Path) -> bool {
    let 設定 = 起動設定::生成する(短時間フレーム数, シェーダー, Some(アセット), 板のシーン)
        .照明なし()
        .粒子あり()
        .開発uiあり()
        .ポストなし();
    必須ステージを実行する(検収の実行名::定数から生成する("dev_ui"), 設定)
}

fn シャドウ(シェーダー: &Path, アセット: &Path) -> bool {
    let 設定 = 起動設定::生成する(短時間フレーム数, シェーダー, Some(アセット), 影のシーン);
    必須ステージを実行する(検収の実行名::定数から生成する("shadow"), 設定)
}

fn フォックス(シェーダー: &Path) -> bool {
    if !フォックスの取得対象.取得済みか() {
        println!("[xtask] Foxアセット未取得のためfox/clothステージをスキップした(cargo xtask fetch-assetsで取得可)");
        return true;
    }
    必須ステージを実行する(
        検収の実行名::定数から生成する("fox"),
        起動設定::生成する(短時間フレーム数, シェーダー, None, キツネのシーン),
    )
}

fn 布(シェーダー: &Path, アセット: &Path) -> bool {
    let 設定 = 起動設定::生成する(短時間フレーム数, シェーダー, Some(アセット), 板のシーン)
        .照明なし()
        .布あり();
    必須ステージを実行する(検収の実行名::定数から生成する("cloth"), 設定)
}

/// ポスト処理を有効に保ったままリサイズ・最小化・復帰を踏む。ポスト処理資源(HDRターゲット・光のにじみピラミッド・
/// 光のにじみ・明るさの圧縮)がスワップチェーン再構築で作り直される経路は、リサイズを踏む唯一のステージであるquadが
/// `--no-post`のため他のどのステージも通らない。ピクセル判定は持たず、合否はvalidation件数と、
/// 論理デバイス破棄前のGPUメモリ残数検査(残っていればpanicで異常終了する)で決まる。
fn ポスト有効リサイズ(シェーダー: &Path, アセット: &Path) -> bool {
    let 設定 = 起動設定::生成する(短時間フレーム数, シェーダー, Some(アセット), 板のシーン)
        .照明なし()
        .ウィンドウ再構築検証あり();
    必須ステージを実行する(検収の実行名::定数から生成する("post_resize"), 設定)
}
