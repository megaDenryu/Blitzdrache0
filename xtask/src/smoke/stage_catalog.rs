//! スモーク検証の各ステージが読むシーンの台帳。担当するのはシーンの綴りを1箇所へ置くことだけであり、
//! どのステージがどの機能を足すかは`stages`が、起動条件の保持は`launch_setting`が持つ。

use crate::acceptance::{描画フレーム数, 検収シーン名};

/// ホットリロードと厳密ピクセル判定を通すステージの枚数。書き換えの検知と再コンパイルを待つため長く回す。
pub(super) const 四角形フレーム数: 描画フレーム数 = 描画フレーム数::生成する(600);
/// 書き換えを持たないステージの枚数。経路を一度通せば足りる。
pub(super) const 短時間フレーム数: 描画フレーム数 = 描画フレーム数::生成する(120);

pub(super) const 板のシーン: 検収シーン名 = 検収シーン名::生成する("quad");
pub(super) const ヘルメットのシーン: 検収シーン名 = 検収シーン名::生成する("helmet");
pub(super) const 影のシーン: 検収シーン名 = 検収シーン名::生成する("shadow_scene");
pub(super) const キツネのシーン: 検収シーン名 = 検収シーン名::生成する("fox");
