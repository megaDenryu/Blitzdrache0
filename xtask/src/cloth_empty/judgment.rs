//! 布ありと布なしの2実行に対する判定。受け取るのは実行結果と計数、返すのは合否である。
//! 「通常の描画入力が0件」は、群が候補として読み込まれた上でシーンと全距離区分の可視数と発行数が0であることで示す。
//! 群を1つも持たないシーンでも発行数は0になるため、候補数を同時に見なければ状態を取り違える。
//! 記録側のパイプライン切替の実数もここで固定する。通常の描画対象が1件も無いため、切替の数はそのまま布が束縛した回数になる
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段6の検収ゲート(v))。

use crate::report_parse::{全パスを並べる, 計数報告};
use crate::vegetation_run::実行結果;

pub(super) fn 入力が空であることを検査する(名前: &str, 計数: &計数報告) -> Result<(), String> {
    for (パス名, パス) in 全パスを並べる(計数) {
        if パス.候補数 == 0 {
            return Err(format!("{名前}の実行で{パス名}の候補が0体である: 群が読み込まれていない"));
        }
        if パス.可視数 != 0 || パス.発行数 != 0 {
            return Err(format!(
                "{名前}の実行で{パス名}の入力が空になっていない: 候補{}体のうち可視{}体、発行{}件",
                パス.候補数, パス.可視数, パス.発行数
            ));
        }
    }
    if 計数.validation件数 != 0 {
        return Err(format!("{名前}の実行でvalidationが{}件出た", 計数.validation件数));
    }
    Ok(())
}

/// 布が束縛するパイプラインの回数。通常の描画対象が1件も無いフレームでは、シーンパスも各距離区分のシャドウパスも
/// 布が自分のパイプラインを1回だけ束縛する。布なしの実行では束縛も描画も1回も起きない。
pub(super) fn 布の段階切替を検査する(名前: &str, 計数: &計数報告, 布あり: bool) -> Result<(), String> {
    let 期待する回数 = u64::from(布あり);
    for (パス名, パス) in 全パスを並べる(計数) {
        if パス.パイプライン切替 != 期待する回数 || パス.描画数 != 期待する回数 {
            return Err(format!(
                "{名前}の実行で{パス名}のパイプライン切替{}回・描画{}回が、期待する{期待する回数}回と違う",
                パス.パイプライン切替, パス.描画数
            ));
        }
        if パス.材質切替 != 0 {
            return Err(format!(
                "{名前}の実行で{パス名}が材質切替を{}回数えた(布は論理的な材質を持たない)",
                パス.材質切替
            ));
        }
    }
    Ok(())
}

/// 布ありの実行だけが画素を描いたことを、2つの読み戻し画像の差で見る。差が0画素なら布は1画素も描けていない。
pub(super) fn 布だけが画素を描くことを検査する(布あり: &実行結果, 布なし: &実行結果) -> Result<usize, String> {
    if 布あり.幅 != 布なし.幅 || 布あり.高さ != 布なし.高さ {
        return Err(format!(
            "2実行の読み戻し寸法が違う: 布あり{}x{}、布なし{}x{}",
            布あり.幅, 布あり.高さ, 布なし.幅, 布なし.高さ
        ));
    }
    let 差の画素数 = 布あり
        .rgba8
        .chunks_exact(4)
        .zip(布なし.rgba8.chunks_exact(4))
        .filter(|(左, 右)| 左 != 右)
        .count();
    if 差の画素数 == 0 {
        return Err("布ありと布なしの読み戻し画像が完全に一致した: 布が1画素も描かれていない".to_string());
    }
    Ok(差の画素数)
}
