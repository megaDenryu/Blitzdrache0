//! 布ありと布なしの2実行に対する判定。受け取るのは実行結果と計数、返すのは合否である。
//! 「通常の描画入力が0件」は、群が候補として読み込まれた上でシーンと全距離区分の可視数と発行数が0であることで示す。
//! 群を1つも持たないシーンでも発行数は0になるため、候補数を同時に見なければ状態を取り違える。
//! 記録側のパイプライン切替の実数もここで固定する。通常の描画対象が1件も無いため、切替の数はそのまま布が束縛した回数になる
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段6の検収ゲート(v))。

use crate::acceptance::{判定の名前, 判定の破れ, 読み戻し画像};
use crate::report_parse::{全パスを並べる, 計数報告};

const 布ありと布なしで違った画素: 判定の名前 =
    判定の名前::定数から生成する("布ありと布なしの読み戻し画像で違った画素(布が描かれていれば1画素以上ある)");

pub(super) fn 入力が空であることを検査する(名前: &str, 計数: &計数報告) -> Result<(), 判定の破れ> {
    for (パス名, パス) in 全パスを並べる(計数) {
        if パス.候補数 == 0 {
            return Err(パスの候補の判定名(名前, &パス名).あるはずのものが無い破れ());
        }
        入力が空であることの判定名(名前, &パス名, "可視数", パス.候補数).零件であることを課す(パス.可視数)?;
        入力が空であることの判定名(名前, &パス名, "発行数", パス.候補数).零件であることを課す(パス.発行数)?;
    }
    検証層の指摘の判定名(名前).零件であることを課す(計数.validation件数)
}

/// 布が束縛するパイプラインの回数。通常の描画対象が1件も無いフレームでは、シーンパスも各距離区分のシャドウパスも
/// 布が自分のパイプラインを1回だけ束縛する。布なしの実行では束縛も描画も1回も起きない。
pub(super) fn 布の段階切替を検査する(名前: &str, 計数: &計数報告, 布あり: bool) -> Result<(), 判定の破れ> {
    let 期待する回数 = u64::from(布あり);
    for (パス名, パス) in 全パスを並べる(計数) {
        記録側の回数の判定名(名前, &パス名, "パイプライン切替").一致を課す(パス.パイプライン切替, 期待する回数)?;
        記録側の回数の判定名(名前, &パス名, "描画").一致を課す(パス.描画数, 期待する回数)?;
        材質切替の判定名(名前, &パス名).零件であることを課す(パス.材質切替)?;
    }
    Ok(())
}

/// 布ありの実行だけが画素を描いたことを、2つの読み戻し画像の差で見る。差が0画素なら布は1画素も描けていない。
pub(super) fn 布だけが画素を描くことを検査する(
    布あり: &読み戻し画像, 布なし: &読み戻し画像
) -> Result<usize, 判定の破れ> {
    寸法が同じであることの判定名(布あり, 布なし).真であることを課す(布あり.寸法が同じか(布なし))?;
    let 差の画素数 = 布あり.画素列().zip(布なし.画素列()).filter(|(左, 右)| 左 != 右).count();
    if 差の画素数 == 0 {
        return Err(布ありと布なしで違った画素.あるはずのものが無い破れ());
    }
    Ok(差の画素数)
}

fn パスの候補の判定名(名前: &str, パス名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{名前}の実行の{パス名}の候補(群が読み込まれていれば1体以上ある)"))
}

fn 入力が空であることの判定名(名前: &str, パス名: &str, 量の名前: &str, 候補数: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{名前}の実行の{パス名}の{量の名前}(候補{候補数}体はどちらの視錐台にも入らないため入力は空になる)"
    ))
}

fn 記録側の回数の判定名(名前: &str, パス名: &str, 量の名前: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{名前}の実行の{パス名}の{量の名前}の回数"))
}

fn 材質切替の判定名(名前: &str, パス名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{名前}の実行の{パス名}が数えた材質切替(布は論理的な材質を持たない)"))
}

fn 検証層の指摘の判定名(名前: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{名前}の実行で出た検証層の指摘"))
}

fn 寸法が同じであることの判定名(布あり: &読み戻し画像, 布なし: &読み戻し画像) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "2実行の読み戻し寸法が同じであること(布あり{}、布なし{})",
        布あり.寸法の綴り(),
        布なし.寸法の綴り()
    ))
}
