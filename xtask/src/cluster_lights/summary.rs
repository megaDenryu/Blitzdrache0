//! 測った値を表と要約の1行へ綴る工程。受け取るのは件数ごとの結果と屋内の測りと絵のパス、返すのは要約の文字列である。
//! 判定はこの工程が行わない。判定は入口が持ち、ここは読める形に並べるだけである。

use std::path::Path;

use super::interior::屋内の測り;
use super::scale::{件数ごとの結果, 反復回数};

pub(super) fn 表を表示する(結果一覧: &[件数ごとの結果]) {
    println!("光の件数ごとのGPU時間と割り当て(各{反復回数}回の中央値):");
    println!(
        "  光の件数 | クラスタの選別ミリ秒 | シーン描画ミリ秒 | 光を持つセル数 | 総件数 | 最大件数 | 平均件数 | 絞りの比 | 偽陽性件数 | 偽陽性率"
    );
    for 結果 in 結果一覧 {
        println!(
            "  {:>8} | {:>16.4} | {:>12.4} | {:>14} | {:>6} | {:>8} | {:>8.4} | {:>8.6} | {:>10} | {:>8.6}",
            結果.光の件数,
            結果.選別ミリ秒,
            結果.シーン描画ミリ秒,
            結果.割り当て.光を持つセル数,
            結果.割り当て.総件数,
            結果.割り当て.最大件数,
            結果.割り当て.平均件数,
            結果.割り当て.絞りの比,
            結果.割り当て.偽陽性件数,
            結果.割り当て.偽陽性率
        );
    }
}

pub(super) fn 要約を組む(結果一覧: &[件数ごとの結果], 屋内: &屋内の測り, 夜の絵: &Path) -> String {
    let 上限 = 結果一覧.last();
    let 上限の記述 = 上限.map_or_else(
        || "光の件数を1つも測れなかった".to_string(),
        |結果| {
            format!(
                "光{}件でセル総数{}・光を持つセル数{}・総件数{}(絞りの比{:.6})・最大件数{}・偽陽性率{:.6}、選別{:.4}ms",
                結果.光の件数,
                結果.割り当て.セル総数,
                結果.割り当て.光を持つセル数,
                結果.割り当て.総件数,
                結果.割り当て.絞りの比,
                結果.割り当て.最大件数,
                結果.割り当て.偽陽性率,
                結果.選別ミリ秒
            )
        },
    );
    format!(
        "{上限の記述}、屋内の平均輝度は灯あり{:.1}・灯なし{:.1}で比{:.2}、絵は{}と{}",
        屋内.灯ありの平均輝度,
        屋内.灯なしの平均輝度,
        屋内.灯ありの平均輝度 / 屋内.灯なしの平均輝度,
        夜の絵.display(),
        屋内.絵.display()
    )
}
