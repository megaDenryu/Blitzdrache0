//! GPU時間の表の読み取りの検査。確かめるのは、窓が満ちた表から2つの区間の中央値を読めること、
//! 窓が満ちていない表を型付きの失敗にすること、区間が表に無い表を失敗にすることである。
//!
//! 窓が満ちていない表の拒否を検査するのは、この検査が無いと「60フレーム窓のp50」と称した別の量の表が
//! 成功として出るためである。破れは値の大小に出るだけで、表の見た目には出ない。

#![allow(clippy::unwrap_used)]

use super::gpu_time::取り出す;
use crate::acceptance::{検収の実行名, 終了時報告};

/// 試験用の終了時報告。読むのは標準出力だけであるため、標準エラーは空でよい。
fn 報告を組む(標準出力: &str) -> 終了時報告 {
    終了時報告::取り込む(&検収の実行名::定数から生成する("gpu_time_tests"), 標準出力.to_string(), String::new())
}

fn 表を組む(選別の標本: usize, シーン描画の標本: usize) -> String {
    format!(
        "パス別GPU時間(直近60フレームの窓):\n  クラスタの選別: 0.0952 (p50 0.0932 / p95 0.1055 / 標本{選別の標本}) ms\n  シーン描画: 0.5837 (p50 0.5700 / p95 0.9100 / 標本{シーン描画の標本}) ms\n"
    )
}

#[test]
fn 窓が満ちた表から中央値を読む() {
    let 実測 = 取り出す(&報告を組む(&表を組む(60, 60))).unwrap();
    assert!((実測.選別ミリ秒 - 0.0932).abs() < 1.0e-9);
    assert!((実測.シーン描画ミリ秒 - 0.5700).abs() < 1.0e-9);
}

#[test]
fn 窓が満ちていない表を失敗にする() {
    assert!(
        取り出す(&報告を組む(&表を組む(10, 60))).is_err(),
        "選別の窓が満ちていない表を受けてしまった"
    );
    assert!(
        取り出す(&報告を組む(&表を組む(60, 59))).is_err(),
        "シーン描画の窓が満ちていない表を受けてしまった"
    );
}

#[test]
fn 区間が無い表を失敗にする() {
    let 表 = "パス別GPU時間(直近60フレームの窓):\n  シーン描画: 0.5837 (p50 0.5700 / p95 0.9100 / 標本60) ms\n";
    assert!(取り出す(&報告を組む(表)).is_err());
}

#[test]
fn 見出しが無い出力を失敗にする() {
    assert!(取り出す(&報告を組む("何も出ていない\n")).is_err());
}
