//! 光の件数を振って夜の世界を測る工程。受け取るのは出力先、返すのは件数ごとの結果の並びである。
//!
//! 同じ件数を3回走らせるのは、単発の実行から実行間の分散と実在する差を区別できないためである
//! (参照: `_doc/計画/評価軸.md`「3.4 計測の再現性」)。3回のうち中央の値を代表にする。
//!
//! 件数を1・8・32・64に取るのは、1件が第3段階までの既定と同じ形であり、64件が世界が宣言できる上限だからである。
//! あいだの2点は、件数を倍々に振ったときGPU時間が件数に比例するのか頭打ちになるのかを読むための点である。

use blitz_math::{パーセンタイル順位, 昇順に並べた標本列, 順位から添字を選ぶ規則};

use super::assignment::割り当ての統計;
use super::gpu_time::区間の中央値;
use super::{assignment, gpu_time};
use crate::acceptance::{判定の名前, 描画検収の実行環境, 検収の実行名, 検収エラー};
use crate::multi_light_world::{run, world};

/// 中央の値が読む順位と、添字を選ぶ規則。寄せる前は`件数 ÷ 2`の添字であり、この規則がその式に当たる。
const 中央の順位: f32 = 50.0;
const 添字を選ぶ規則: 順位から添字を選ぶ規則 = 順位から添字を選ぶ規則::件数を基準にした切り捨て;

/// 振る光の件数。
pub(super) const 光の件数一覧: [usize; 4] = [1, 8, 32, 64];

/// 指定した件数と食い違うと、件数を振ったつもりの計測が別の件数の繰り返しになる。
const GPUが宣言した光の件数: 判定の名前 = 判定の名前::定数から生成する("GPUが宣言した光の件数");
/// 反復が1回も走らなければ割り当ての統計を1つも採れない。反復回数を0にした改定がここで落ちる。
const 反復の実行: 判定の名前 = 判定の名前::定数から生成する("1つの光の件数に対する反復の実行");

/// 同じ件数を何回走らせるか。
pub(super) const 反復回数: usize = 3;

pub(super) struct 件数ごとの結果 {
    pub(super) 光の件数: usize,
    pub(super) 選別ms: f64,
    pub(super) シーン描画ms: f64,
    pub(super) 割り当て: 割り当ての統計,
}

pub(super) fn 光の件数を振って測る(実行環境: &描画検収の実行環境) -> Result<Vec<件数ごとの結果>, 検収エラー> {
    光の件数一覧.iter().map(|件数| 一件数を測る(実行環境, *件数)).collect()
}

fn 一件数を測る(実行環境: &描画検収の実行環境, 光の件数: usize) -> Result<件数ごとの結果, 検収エラー> {
    let 件数文字列 = 光の件数.to_string();
    let mut 選別一覧 = Vec::with_capacity(反復回数);
    let mut シーン描画一覧 = Vec::with_capacity(反復回数);
    let mut 最後の割り当て = None;
    for 回 in 1..=反復回数 {
        let 実行名の文字列 = format!("night_x{光の件数}_{回}");
        let 結果 = 実行環境.描いて読み戻す(
            検収の実行名::生成する(&実行名の文字列)?,
            &run::起動指定を組み立てる(
                world::夜のシーン,
                world::計測の枚数,
                &["--sky", "--time-of-day", world::夜の一日内秒, "--local-light-count", &件数文字列, "--report-gpu-times", "--report-cluster-assignment"],
            ),
        )?;
        let 区間の中央値 { 選別ms, シーン描画ms } = gpu_time::区間の中央値を取り出す(結果.報告())?;
        選別一覧.push(選別ms);
        シーン描画一覧.push(シーン描画ms);
        最後の割り当て = Some(assignment::割り当ての統計を取り出す(結果.報告())?);
    }
    let 割り当て = 最後の割り当て.ok_or_else(|| 検収エラー::from(反復の実行.あるはずのものが無い破れ()))?;
    宣言された件数を確かめる(&割り当て, 光の件数)?;
    Ok(件数ごとの結果 {
        光の件数,
        選別ms: 中央の値(&mut 選別一覧),
        シーン描画ms: 中央の値(&mut シーン描画一覧),
        割り当て,
    })
}

/// 指定した件数がそのままGPUの宣言件数になっているかを確かめる。ここが食い違うと、件数を振ったつもりの
/// 計測が別の件数の繰り返しになる。
fn 宣言された件数を確かめる(割り当て: &割り当ての統計, 光の件数: usize) -> Result<(), 検収エラー> {
    Ok(GPUが宣言した光の件数.一致を課す(割り当て.宣言光数, u64::try_from(光の件数).unwrap_or(u64::MAX))?)
}

/// 反復のうち中央の値。反復回数は奇数であるため、並べ替えた真ん中が1つに決まる。
/// 1件も無いときに非数を返すのは、続く表示がその桁を数として書けないことを読み手へ見せるためである。
fn 中央の値(一覧: &mut [f64]) -> f64 {
    let 標本列 = 昇順に並べた標本列::並べ替えて生成する(一覧);
    標本列.パーセンタイル値を求める(パーセンタイル順位::百分率から生成する(中央の順位), 添字を選ぶ規則).unwrap_or(f64::NAN)
}
