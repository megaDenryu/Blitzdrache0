//! 屋内の灯ありと灯なしの平均輝度から合否を決める工程。受け取るのは2つの平均輝度、返すのは比か失敗の理由である。
//!
//! 比を作る前に両側が有限かつ正であることを課すのは、灯なしが0のとき0で割った答えが非数になり、
//! 「非数は下限より小さくない」という比較の性質で全黒の絵が成功として通るためである。
//! 灯ありが0であることも、屋内が1画素も照らされていないという別の破れであり、比の大小より先に落とす。
//!
//! 灯なしが0になるのは、環境光も方向光も屋内へ1つも届いていないときである。その状態は世界の宣言が壊れた印であり、
//! 比が無限に大きい成功として通してはならない。

/// 灯ありの屋内が灯なしより明るいと認める倍率。2026-08-10の実測は灯あり195.0・灯なし6.2で比31.6であり、
/// この下限はその15分の1である。灯が1件も効かなくなれば比は1へ落ちるため、この位置で十分に分かれる。
pub(super) const 明るさ比の下限: f64 = 2.0;

pub(super) fn 明るさの比を判定する(灯ありの平均輝度: f64, 灯なしの平均輝度: f64) -> Result<f64, String> {
    有限かつ正であることを確かめる("灯あり", 灯ありの平均輝度)?;
    有限かつ正であることを確かめる("灯なし", 灯なしの平均輝度)?;
    let 比 = 灯ありの平均輝度 / 灯なしの平均輝度;
    if !比.is_finite() {
        return Err(format!(
            "屋内の明るさの比が有限でない(灯あり{灯ありの平均輝度}・灯なし{灯なしの平均輝度})"
        ));
    }
    if 比 < 明るさ比の下限 {
        return Err(format!(
            "屋内の灯ありと灯なしの平均輝度の比{比:.2}が下限{明るさ比の下限}未満だった(灯あり{灯ありの平均輝度:.1}・灯なし{灯なしの平均輝度:.1}): 屋内へ点光源が届いていない"
        ));
    }
    Ok(比)
}

fn 有限かつ正であることを確かめる(条件名: &str, 平均輝度: f64) -> Result<(), String> {
    if 平均輝度.is_finite() && 平均輝度 > 0.0 {
        return Ok(());
    }
    Err(format!(
        "屋内の{条件名}の平均輝度が有限かつ正でない({平均輝度}): 測った矩形が全黒か、読み戻しが壊れている"
    ))
}

#[cfg(test)]
mod tests {
    use super::{明るさの比を判定する, 明るさ比の下限};

    #[test]
    fn 下限を超える比を受ける() {
        assert_eq!(明るさの比を判定する(195.0, 6.2).map(|比| (比 * 100.0).round()), Ok(3145.0));
    }

    #[test]
    fn 下限に満たない比を失敗にする() {
        assert!(明るさの比を判定する(6.0, 6.0).is_err());
        assert!(明るさの比を判定する(6.0 * 明るさ比の下限 - 0.1, 6.0).is_err());
    }

    /// 0で割った比は非数になり、非数は下限より小さくないため、この検査が無いと全黒の絵が成功として通る。
    #[test]
    fn 両側が0の入力を失敗にする() {
        assert!(明るさの比を判定する(0.0, 0.0).is_err());
    }

    #[test]
    fn 灯なしが0の入力を失敗にする() {
        assert!(明るさの比を判定する(195.0, 0.0).is_err());
    }

    #[test]
    fn 灯ありが0の入力を失敗にする() {
        assert!(明るさの比を判定する(0.0, 6.2).is_err());
    }

    #[test]
    fn 有限でない入力を失敗にする() {
        assert!(明るさの比を判定する(f64::NAN, 6.2).is_err());
        assert!(明るさの比を判定する(195.0, f64::NAN).is_err());
        assert!(明るさの比を判定する(f64::INFINITY, 6.2).is_err());
    }
}
