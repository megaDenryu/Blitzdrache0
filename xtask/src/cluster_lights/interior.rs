//! 屋内の世界を灯ありと灯なしの2条件で撮り、屋内が点光源で照らされていることを画素で見る工程。
//! 受け取るのは出力先、返すのは2条件の明るさと灯ありの絵のパスである。
//!
//! 画面中央の矩形を測るのは、カメラが戸口を正面に据えており、戸口の向こうの屋内が常にその矩形へ入るためである
//! (`crates/blitz_app/src/app/scene_camera/stone_hut_doorway_view.rs`が構図を持つ)。色でなく領域で切るのは、
//! 灯を消した条件では屋内がほぼ黒になり、色による切り出しが成立しないためである。
//!
//! 平均輝度は3つの成分の相加平均で測る。`cargo xtask cloth-night`の布の平均輝度と同じ測り方であり、
//! 明るいか暗いかを比べるだけの用途に重み付きの相対輝度を持ち込まない。
//!
//! 注意: この段の点光源は影を持たないため、灯は壁を抜けて外側の面も照らす。それでも屋内の矩形が明るくなるのは
//! 灯が屋内にあるからであり、この判定は「屋内へ光が届いていること」を見る。壁が光を遮ることの判定は第5段階の仕事である。

use std::path::{Path, PathBuf};

use crate::acceptance::{検収の実行名, 画素の横位置, 画素の縦位置, 読み戻しの書き出し先};
use crate::multi_light_world::{run, world};

/// 屋内を測る矩形の、画面の幅と高さに対する半分の割合を百分率で置く。戸口の内側だけを含み、小屋の外壁を含まない大きさである。
/// 百分率の整数で持つのは、画素数を実数へ写してから整数へ戻す往復を作らないためである。
const 矩形の半分の百分率: usize = 8;

pub(super) struct 屋内の測り {
    pub(super) 灯ありの平均輝度: f64,
    pub(super) 灯なしの平均輝度: f64,
    pub(super) 絵: PathBuf,
}

pub(super) fn 測る(出力先: &Path) -> Result<屋内の測り, String> {
    let 灯あり = 一条件を撮る(出力先, "hut_lit", &[])?;
    let 灯なし = 一条件を撮る(出力先, "hut_unlit", &["--local-light-count", "0"])?;
    Ok(屋内の測り {
        灯ありの平均輝度: 灯あり.0,
        灯なしの平均輝度: 灯なし.0,
        絵: 灯あり.1,
    })
}

fn 一条件を撮る(出力先: &Path, 名前: &str, 追加引数: &[&str]) -> Result<(f64, PathBuf), String> {
    let 実行名 = 検収の実行名::生成する(名前)?;
    let 書き出し先 = 読み戻しの書き出し先::出力ディレクトリの中に決める(出力先, 実行名);
    let 結果 = run::走らせる(&run::描画条件 {
        シーン名: world::屋内のシーン,
        アセットルート: world::屋内のアセットルート,
        枚数: world::絵の枚数,
        書き出し先: &書き出し先,
        追加引数,
    })?;
    let 平均輝度 = 中央の矩形の平均輝度(&結果.画像);
    Ok((平均輝度, 書き出し先.目視用の絵へ変換する()?))
}

fn 中央の矩形の平均輝度(画像: &crate::acceptance::読み戻し画像) -> f64 {
    let (幅, 高さ) = (画像.幅().画素数(), 画像.高さ().画素数());
    let 横の半分 = 割合を画素へ写す(幅);
    let 縦の半分 = 割合を画素へ写す(高さ);
    let (中心の横, 中心の縦) = (幅 / 2, 高さ / 2);
    let mut 合計 = 0.0;
    let mut 画素数 = 0_usize;
    for 縦 in 中心の縦.saturating_sub(縦の半分)..(中心の縦 + 縦の半分).min(高さ) {
        for 横 in 中心の横.saturating_sub(横の半分)..(中心の横 + 横の半分).min(幅) {
            let 画素 = 画像.座標の画素(画素の横位置::生成する(横), 画素の縦位置::生成する(縦));
            合計 += (f64::from(画素[0]) + f64::from(画素[1]) + f64::from(画素[2])) / 3.0;
            画素数 += 1;
        }
    }
    if 画素数 == 0 {
        0.0
    } else {
        合計 / 画素数を実数へ写す(画素数)
    }
}

fn 割合を画素へ写す(長さ: usize) -> usize {
    長さ * 矩形の半分の百分率 / 100
}

fn 画素数を実数へ写す(値: usize) -> f64 {
    f64::from(u32::try_from(値).unwrap_or(u32::MAX))
}
