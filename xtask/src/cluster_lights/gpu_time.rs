//! パス別GPU時間の表から、この検収が読む2つの区間の中央値を取り出す工程。受け取るのは終了時報告、返すのは2つの値である。
//!
//! 平均でなく中央値を読むのは、跳ねた標本に引きずられない値で光の件数どうしを比べるためである。
//! 表の綴りは`crates/blitz_app/src/reports/gpu_time_table.rs`の出力と一致させている。
//!
//! **標本数が窓の長さに満ちていることを必ず確かめる。** 満ちていない窓のp50は「直近60フレームの中央値」ではなく、
//! 撮った枚数ぶんだけの中央値であり、条件どうしを並べて読む根拠にならない。枚数が足りない実行を成功として
//! 通すと、その表は「60フレーム窓のp50」と称した別の量の表になる。

use crate::acceptance::{判定の名前, 報告の区画, 報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

const 見出し: 報告の見出し = 報告の見出し::定数から生成する("パス別GPU時間");

/// 分布を求める窓が保つ標本の数。正本は`crates/blitz_render/src/gpu_pass_timing.rs`の`窓の標本数`であり、
/// xtaskが外部クレートへ依存しない方針のため値を持ち直している。この二重定義は`cargo xtask conform`の定数一致検査へ登録してある。
const 窓の標本数: usize = 60;
const 選別の区間名: &str = "クラスタの選別";
const シーン描画の区間名: &str = "シーン描画";
/// 中央値の鍵。分布の行では開き括弧が鍵へ触れているため、末尾一致で探す。
const 中央値の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("p50");
/// 標本数は「標本60)」の形で1語に続くため、鍵の後ろの残りから閉じ括弧を落として読む。
const 標本数の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("標本");

pub(crate) struct 区間の中央値 {
    pub(super) 選別ミリ秒: f64,
    pub(super) シーン描画ミリ秒: f64,
}

pub(super) fn 取り出す(報告: &終了時報告) -> Result<区間の中央値, 検収エラー> {
    let 区画 = 報告.見出しの区画(見出し)?;
    Ok(区間の中央値 {
        選別ミリ秒: 中央値を読む(&区画, 選別の区間名)?,
        シーン描画ミリ秒: 中央値を読む(&区画, シーン描画の区間名)?,
    })
}

fn 中央値を読む(区画: &報告の区画, 区間名: &str) -> Result<f64, 検収エラー> {
    let 接頭辞 = 報告の見出し::組み立てた綴りから生成する(format!("{区間名}:"));
    let 行 = 区画.接頭辞の行(&接頭辞)?;
    窓が満ちていることを確かめる(行, 区間名)?;
    行.鍵に結ばれた数(&中央値の鍵, 鍵に値が結ばれる形::この綴りで終わる語の次が値である)
}

/// 「標本60)」の形で括弧の中に並ぶ標本数を読み、窓の長さに満ちていることを課す。
fn 窓が満ちていることを確かめる(行: &報告の行, 区間名: &str) -> Result<(), 検収エラー> {
    let 標本数: usize = 行.鍵に結ばれた語から数字だけを読む(&標本数の鍵, 鍵に値が結ばれる形::この綴りに続く残りが値である)?;
    let 判定名 = 判定の名前::組み立てた綴りから生成する(format!(
        "区間{区間名}の分布が採った標本の数(窓の長さに満ちていなければ、このp50は直近{窓の標本数}フレームの中央値ではない)"
    ));
    Ok(判定名.一致を課す(標本数, 窓の標本数)?)
}
