//! 同一の起動の中で撮った2枚の一致を見る工程。受け取るのは出力先、返すのは撮った絵のパスである。
//!
//! 起動をまたがずに比べるのは、GPUの読み戻しがこの機材では時間帯によって非決定になることが分かっているためである
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「検収戦略(判断i)」の3)。同一起動の中の最終フレームと
//! その1つ前を撮り、静止した世界であるからバイト単位で一致することを課す。
//!
//! この判定が成立するのは、この世界が布を1枚も持たないためである。布の画素は実行のたびに揺れる。
//!
//! 絵のバイト一致に加えて、その実行が出した割り当ての報告行どうしも比べる。絵は最終の色だけを写すため、
//! セルへの割り当てが揺れても同じ画素へ落ち着けば絵の一致だけでは捉えられないためである。

use std::path::PathBuf;

use super::assignment;
use crate::acceptance::{判定の名前, 描画検収の実行環境, 検収の実行名, 検収エラー, 終了時報告};
use crate::multi_light_world::{run, world};

/// 最終フレームの書き出しの基準名。
const 最終フレームの実行名: 検収の実行名 = 検収の実行名::定数から生成する("night");
/// 先行フレームの書き出しの基準名。アプリが最終フレームの名前へ`_preceding`を足して書き出す。
const 先行フレームの実行名: 検収の実行名 = 検収の実行名::定数から生成する("night_preceding");

const 撮った2枚で違った画素: 判定の名前 = 判定の名前::定数から生成する("同一起動の中で撮った2枚で違った画素");
const 撮った2枚のバイト長: 判定の名前 = 判定の名前::定数から生成する("同一起動の中で撮った2枚のバイト長");
/// 本数の下限が2であるのは、先行フレームの書き出しが効いていれば最終フレームとあわせて2本出るためである。
const 割り当ての報告行の本数: 判定の名前 =
    判定の名前::定数から生成する("同一起動の中で出た割り当ての報告行の本数(先行フレームの書き出しが効いていれば2本以上になる)");
const 割り当ての報告行の綴り: 判定の名前 = 判定の名前::定数から生成する("同一起動の中で出た割り当ての報告行の綴り");

pub(super) fn 確かめる(実行環境: &描画検収の実行環境) -> Result<PathBuf, 検収エラー> {
    let 結果 = 実行環境.描いて読み戻す(最終フレームの実行名, &起動指定を組み立てる())?;
    割り当ての行が一致することを確かめる(結果.報告())?;
    let 先行 = 実行環境.同じ置き場の書き出しを読み戻す(先行フレームの実行名)?;
    let 違う画素数 = 違う画素を数える(結果.画像().バイト列(), 先行.バイト列())?;
    撮った2枚で違った画素.零件であることを課す(違う画素数)?;
    結果.書き出し先().目視用の絵へ変換する()
}

fn 起動指定を組み立てる() -> crate::acceptance::アプリの起動指定 {
    run::起動指定を組み立てる(
        world::夜のシーン,
        world::絵の枚数,
        &[
            "--sky",
            "--time-of-day",
            world::夜の一日内秒,
            "--dump-preceding-frame",
            "--report-cluster-assignment",
        ],
    )
}

/// 同じ起動の中で出た割り当ての報告行が全部同じ綴りであることを課す。先行フレームと最終フレームの2行が出るため、
/// 1行しか無い実行は先行フレームの書き出しが効いていないことを意味し、それも失敗にする。
fn 割り当ての行が一致することを確かめる(報告: &終了時報告) -> Result<(), 検収エラー> {
    let 行一覧 = assignment::行一覧を取り出す(報告)?;
    let Some(先頭) = 行一覧.first() else {
        return Err(割り当ての報告行の本数.あるはずのものが無い破れ().into());
    };
    割り当ての報告行の本数.下限を課す(行一覧.len(), 2)?;
    for 行 in &行一覧 {
        割り当ての報告行の綴り.綴りの一致を課す(行.原文(), 先頭.原文())?;
    }
    Ok(())
}

fn 違う画素を数える(左: &[u8], 右: &[u8]) -> Result<usize, 検収エラー> {
    撮った2枚のバイト長.一致を課す(左.len(), 右.len())?;
    Ok(左.chunks_exact(4).zip(右.chunks_exact(4)).filter(|(左, 右)| 左 != 右).count())
}
