//! クラスタの割り当ての報告行の読み取り。受け取るのは終了時報告、返すのは統計の値である。
//! 行の綴りは`crates/blitz_app/src/reports/cluster_assignment.rs`の出力と一致させている。
//!
//! 最後に現れた行を読むのは、先行フレームも書き出す実行では同じ行が2回出るためである。
//! その2行が同じ綴りであることは`determinism`が`行一覧を取り出す`で直に比べる(絵のバイト一致だけでは、
//! 絵に出ない割り当ての揺れを捉えられないためである)。

use crate::acceptance::{判定の名前, 報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

const 語頭: 報告の見出し = 報告の見出し::定数から生成する("クラスタ割り当て");
const 割り当ての報告行: 判定の名前 = 判定の名前::定数から生成する("クラスタ割り当ての報告行");

pub(super) struct 割り当ての統計 {
    pub(super) セル総数: u64,
    pub(super) 宣言光数: u64,
    pub(super) 光を持つセル数: u64,
    pub(super) 総件数: u64,
    pub(super) 最大件数: u64,
    pub(super) 平均件数: f64,
    pub(super) 絞りの比: f64,
    pub(super) 偽陽性件数: u64,
    pub(super) 偽陽性率: f64,
}

/// 割り当ての報告行を出た順に全部返す。1行も無ければ失敗にする。
pub(super) fn 行一覧を取り出す(報告: &終了時報告) -> Result<Vec<報告の行>, 検収エラー> {
    let 行一覧 = 報告.見出しで始まる行の一覧(&語頭);
    if 行一覧.is_empty() {
        return Err(割り当ての報告行.あるはずのものが無い破れ().into());
    }
    Ok(行一覧)
}

pub(super) fn 取り出す(報告: &終了時報告) -> Result<割り当ての統計, 検収エラー> {
    let 行一覧 = 行一覧を取り出す(報告)?;
    let 行 = 行一覧
        .last()
        .ok_or_else(|| 検収エラー::from(割り当ての報告行.あるはずのものが無い破れ()))?;
    Ok(割り当ての統計 {
        セル総数: 整数を読む(行, "セル総数")?,
        宣言光数: 整数を読む(行, "宣言光数")?,
        光を持つセル数: 整数を読む(行, "光を持つセル数")?,
        総件数: 整数を読む(行, "総件数")?,
        最大件数: 整数を読む(行, "最大件数")?,
        平均件数: 小数を読む(行, "平均件数")?,
        絞りの比: 小数を読む(行, "絞りの比")?,
        偽陽性件数: 整数を読む(行, "偽陽性件数")?,
        偽陽性率: 小数を読む(行, "偽陽性率")?,
    })
}

fn 整数を読む(行: &報告の行, 名前: &'static str) -> Result<u64, 検収エラー> {
    行.鍵に結ばれた数(&報告の行の鍵::定数から生成する(名前), 鍵に値が結ばれる形::等号の後ろが値である)
}

fn 小数を読む(行: &報告の行, 名前: &'static str) -> Result<f64, 検収エラー> {
    行.鍵に結ばれた数(&報告の行の鍵::定数から生成する(名前), 鍵に値が結ばれる形::等号の後ろが値である)
}
