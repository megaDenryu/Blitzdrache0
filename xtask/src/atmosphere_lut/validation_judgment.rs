//! validationの観測の判定。担当する工程は「報告の検証層の行を受け取り、指摘が1件でもあれば検収を落とし、
//! 層が機材に無いときはその事実を告知する」ことである。返すのは告知の文であり、値の正しさは判定しない。
//!
//! 値の一致を見る`judgment`と分けるのは、こちらが見るのが「Vulkanの使い方が正しいか」であり、
//! 層が無い機材では観測そのものが成立しないという別の失敗の仕方を持つためである。
//! 層が無いことを不合格にせず告知に留めるのは、検査が層を入れていない機材でも走らなければならないからである。
//! ただし無言では通さない。指摘0件が保証になるのは層が有効だった実行だけである。

use super::parse::検証行;

const 有効の語: &str = "有効";

/// 判定を通ったときに検収の要約へ足す告知。層が有効なら実測の件数、無ければ観測できていないことを述べる。
pub fn 検証を検査する(検証: &検証行) -> Result<String, String> {
    if 検証.件数 != 0 {
        return Err(format!(
            "ヘッドレス実行でvalidationが{}件の指摘を出した(層の状況は{})。指摘の全文はblitz_appの標準エラーにある",
            検証.件数, 検証.状況
        ));
    }
    if 検証.状況 != 有効の語 {
        return Ok(format!(
            "validation層は{}ため、この実行はVulkanの使い方の指摘を1件も観測していない(件数0は保証にならない)",
            検証.状況
        ));
    }
    Ok("validation層が有効な実行で指摘0件である".to_string())
}
