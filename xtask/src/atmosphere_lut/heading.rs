//! 大気のベイク済み画像の読み戻し報告の行の見出し。見出しは行の種類を決める語であり、
//! 読む側は見出しで行を振り分けて許容誤差まで選ぶ。
//!
//! 綴りをこの1つのファイルへ集めるのは、blitz_appが出す語との契約がここだけで保たれるためである。
//! 綴りが片側だけ動くと、その種類の行が1本も読まれないまま「代表テクセルは全部合格」という判定になる。
//! 食い違いは`cargo xtask conform`の綴りの契約の検査が拒む。

use crate::report_heading::報告の見出し;

pub(super) const 検証層の見出し: 報告の見出し = 報告の見出し::定数から生成する("検証層");
pub(super) const 再現性の見出し: 報告の見出し = 報告の見出し::定数から生成する("再現性");
pub(super) const 空中遠近の統計の見出し: 報告の見出し = 報告の見出し::定数から生成する("空中遠近統計");
pub(super) const 空中遠近の代表透過率の見出し: 報告の見出し = 報告の見出し::定数から生成する("空中遠近透過率");

pub(super) const 透過率の統計の見出し: 報告の見出し = 報告の見出し::定数から生成する("透過率統計");
pub(super) const 多重散乱の統計の見出し: 報告の見出し = 報告の見出し::定数から生成する("多重散乱統計");
pub(super) const スカイビューの統計の見出し: 報告の見出し = 報告の見出し::定数から生成する("スカイビュー統計");

pub(super) const 透過率の代表テクセルの見出し: 報告の見出し = 報告の見出し::定数から生成する("透過率代表");
pub(super) const 多重散乱の代表テクセルの見出し: 報告の見出し = 報告の見出し::定数から生成する("多重散乱代表");
pub(super) const スカイビューの代表テクセルの見出し: 報告の見出し = 報告の見出し::定数から生成する("スカイビュー代表");
pub(super) const 空中遠近の代表テクセルの見出し: 報告の見出し = 報告の見出し::定数から生成する("空中遠近代表");

/// 平面のベイク済み画像3枚の統計の見出し。並びは出す側が行を並べる順そのものであり、
/// この順で読んだ一覧が表と判定の並びになる。
pub(super) const 平面の統計の見出し一覧: [報告の見出し; 3] = [透過率の統計の見出し, 多重散乱の統計の見出し, スカイビューの統計の見出し];

/// 代表テクセルの見出し。並びは出す側が行を並べる順そのものである。
pub(super) const 代表テクセルの見出し一覧: [報告の見出し; 4] = [
    透過率の代表テクセルの見出し,
    多重散乱の代表テクセルの見出し,
    スカイビューの代表テクセルの見出し,
    空中遠近の代表テクセルの見出し,
];
