//! 報告の1行から鍵つきの値を取り出す工程。受け取るのは行と鍵の綴り、返すのは整数または実数または語句である。
//! 語の並びに依存せず鍵で参照するのは、報告へ項目を足したときに読み取り側が壊れないようにするためである。

use crate::acceptance::{報告の行, 検収エラー};
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

/// この報告の行は全項目が「鍵=値」の形で並ぶ。
const 値の結ばれ方: 鍵に値が結ばれる形 = 鍵に値が結ばれる形::等号の後ろが値である;

pub(super) fn 語句値(行: &報告の行, 鍵: &'static str) -> Result<String, 検収エラー> {
    行.鍵に結ばれた綴り(&報告の行の鍵::定数から生成する(鍵), 値の結ばれ方)
}

pub(super) fn 整数値(行: &報告の行, 鍵: &'static str) -> Result<usize, 検収エラー> {
    行.鍵に結ばれた数(&報告の行の鍵::定数から生成する(鍵), 値の結ばれ方)
}

pub(super) fn 実数値(行: &報告の行, 鍵: &'static str) -> Result<f64, 検収エラー> {
    行.鍵に結ばれた数(&報告の行の鍵::定数から生成する(鍵), 値の結ばれ方)
}

/// テクセルやボクセルの座標。報告が出す添字はu32であり、u32へ収まらない綴りは報告そのものが壊れていることを意味する。
pub(super) fn 添字値(行: &報告の行, 鍵: &'static str) -> Result<u32, 検収エラー> {
    行.鍵に結ばれた数(&報告の行の鍵::定数から生成する(鍵), 値の結ばれ方)
}
