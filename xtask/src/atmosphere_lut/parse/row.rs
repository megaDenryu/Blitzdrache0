//! 平面のベイク済み画像の報告の行の形と、1行ぶんの読み取り。担当するのは「blitz_appが出す行の項目名と型の対応を持ち、
//! 報告の1行から対応する行の値を組む」ことである。
//!
//! 行の形をここが単独で持つのは、これがblitz_appとxtaskの間の機械可読な契約そのものだからである。
//! 報告側へ項目を足すときに直す場所が1つになり、全文の走査(`parse`)は行の中身を知らずに振り分けだけを行う。
//! 空中遠近ボリュームの行は成分の意味が違うため`aerial_row`が持つ。
//!
//! `検証行`の`状況`が「有効」以外のとき、層が機材に無く、`件数`が0であることは保証にならない。

use super::field::{実数値, 整数値, 添字値, 語句値};
use crate::acceptance::{報告の行, 検収エラー};
use crate::report_heading::報告の見出し;

pub struct 検証行 {
    pub 状況: String, // blitz_appが出す状況の語
    pub 件数: usize,
}

pub struct 再現性行 {
    pub 透過率の不一致: usize,
    pub 多重散乱の不一致: usize,
    pub スカイビューの不一致: usize,
    pub 空中遠近の不一致: usize,
}

pub struct 統計行 {
    pub 見出し: 報告の見出し,
    pub テクセル数: usize,
    pub 非有限: usize,
    pub 負: usize,
    pub 一超え: usize,
    pub 予約が非零: usize,
    pub 最大: f64,
}

pub struct 代表行 {
    pub 見出し: 報告の見出し,
    pub 横: u32,
    pub 縦: u32,
    pub 期待: [f64; 3],
    pub 実測: [f64; 3],
}

pub(super) fn 検証を読む(行: &報告の行) -> Result<検証行, 検収エラー> {
    Ok(検証行 {
        状況: 語句値(行, "状況")?,
        件数: 整数値(行, "件数")?,
    })
}

pub(super) fn 再現性を読む(行: &報告の行) -> Result<再現性行, 検収エラー> {
    Ok(再現性行 {
        透過率の不一致: 整数値(行, "透過率の不一致")?,
        多重散乱の不一致: 整数値(行, "多重散乱の不一致")?,
        スカイビューの不一致: 整数値(行, "スカイビューの不一致")?,
        空中遠近の不一致: 整数値(行, "空中遠近の不一致")?,
    })
}

pub(super) fn 統計を読む(行: &報告の行, 見出し: &報告の見出し) -> Result<統計行, 検収エラー> {
    Ok(統計行 {
        見出し: 見出し.clone(),
        テクセル数: 整数値(行, "テクセル数")?,
        非有限: 整数値(行, "非有限")?,
        負: 整数値(行, "負")?,
        一超え: 整数値(行, "一超え")?,
        予約が非零: 整数値(行, "予約が非零")?,
        最大: 実数値(行, "最大")?,
    })
}

pub(super) fn 代表を読む(行: &報告の行, 見出し: &報告の見出し) -> Result<代表行, 検収エラー> {
    Ok(代表行 {
        見出し: 見出し.clone(),
        横: 添字値(行, "横")?,
        縦: 添字値(行, "縦")?,
        期待: [実数値(行, "期待赤")?, 実数値(行, "期待緑")?, 実数値(行, "期待青")?],
        実測: [実数値(行, "実測赤")?, 実数値(行, "実測緑")?, 実数値(行, "実測青")?],
    })
}
