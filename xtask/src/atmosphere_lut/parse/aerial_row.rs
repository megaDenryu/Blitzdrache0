//! 空中遠近ボリュームの報告の行の形と、1行ぶんの読み取り。担当するのは「ボリューム統計と代表透過率の2種類の行について、
//! 項目名と型の対応を持ち、空白で切った語の一覧から値を組む」ことである。
//!
//! 平面のベイク済み画像の行と別に持つのは、4成分目が予約でなく代表透過率であることに由来して行そのものが別だからである。
//! 統計は予約が0であることを見る欄を持たず値域外の件数を持ち、代表は奥の添字を持ち3成分でなく1成分を運ぶ。

use super::field::{実数値, 整数値, 添字値};

/// 空中遠近ボリュームの統計。予約が0であることを見る欄をこちらは持たない。
pub struct ボリューム統計行 {
    pub ボクセル数: usize,
    pub 非有限: usize,
    pub 負: usize,
    pub 透過率が値域外: usize,
    pub 最大: f64,
}

/// 空中遠近の代表ボクセルの代表透過率。散乱と別の行にするのは、判定が許容の見方を分けるためである。
pub struct 透過率行 {
    pub 横: u32,
    pub 縦: u32,
    pub 奥: u32,
    pub 期待: f64,
    pub 実測: f64,
}

pub(super) fn ボリューム統計を読む(語一覧: &[&str]) -> Result<ボリューム統計行, String> {
    Ok(ボリューム統計行 {
        ボクセル数: 整数値(語一覧, "ボクセル数")?,
        非有限: 整数値(語一覧, "非有限")?,
        負: 整数値(語一覧, "負")?,
        透過率が値域外: 整数値(語一覧, "透過率が値域外")?,
        最大: 実数値(語一覧, "最大")?,
    })
}

pub(super) fn 透過率を読む(語一覧: &[&str]) -> Result<透過率行, String> {
    Ok(透過率行 {
        横: 添字値(語一覧, "横")?,
        縦: 添字値(語一覧, "縦")?,
        奥: 添字値(語一覧, "奥")?,
        期待: 実数値(語一覧, "期待")?,
        実測: 実数値(語一覧, "実測")?,
    })
}
