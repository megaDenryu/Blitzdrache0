//! 代表テクセルの行の見出しと縦位置から、その行に使う許容を選ぶ工程。
//! 受け取るのは見出しと縦位置、返すのは許容である。許容の値そのものは`thresholds`が持つ。
//!
//! 選ぶ規則を値の台帳と分けて持つのは、2つが別の理由で動くためである。値は実測と余裕の取り方で動き、
//! 規則は報告に出る行の種類が増減したときに動く。

use super::heading;
use super::thresholds::{
    スカイビューの許容, スカイビュー地平線近傍の許容, 多重散乱の許容, 空中遠近の許容, 許容, 透過率の許容
};
use crate::report_heading::報告の見出し;

/// スカイビューの代表テクセルのうち地平線近傍とみなす縦位置。テクセル数20736(横192・縦108)の
/// 中央53.5をまたぐ2行であり、`スカイビュー地平線近傍の許容`の対象を選ぶ。
const スカイビュー地平線近傍の縦: [u32; 2] = [53, 54];

/// 見出しと縦位置から許容を選ぶ。縦位置が要るのはスカイビューだけであり、他の見出しでは無視する。
pub fn 見出しから許容を選ぶ(見出し: &報告の見出し, 縦: u32) -> 許容 {
    if 見出し == &heading::多重散乱の代表テクセルの見出し {
        return 多重散乱の許容;
    }
    if 見出し == &heading::スカイビューの代表テクセルの見出し {
        return スカイビューの縦位置から許容を選ぶ(縦);
    }
    if 見出し == &heading::空中遠近の代表テクセルの見出し {
        return 空中遠近の許容;
    }
    透過率の許容
}

/// 地平線近傍の2行だけ別枠の緩い許容を使う。理由は`thresholds`の許容の宣言に書いてある。
fn スカイビューの縦位置から許容を選ぶ(縦: u32) -> 許容 {
    if スカイビュー地平線近傍の縦.contains(&縦) {
        スカイビュー地平線近傍の許容
    } else {
        スカイビューの許容
    }
}
