//! 大気のベイク済み画像報告を、判定が読む行の構造へ切り出す工程。
//! 受け取るのは終了時報告、返すのは検証層・再現性・統計・代表テクセルの4種類の行である。
//! 1つの行から鍵つきの値を取り出す部分は`field`、行ごとの項目の対応は平面のベイク済み画像が`row`・
//! 空中遠近ボリュームが`aerial_row`が持つ。
//!
//! 見出しごとに行を集めるのは、出す側が種類ごとにまとめて並べるためである。見出しの並びを出す側の順に揃えてあり、
//! 読んだ一覧の並びは全文を上から走査したときと同じになる。

mod aerial_row;
mod field;
mod row;

use super::heading;

pub use aerial_row::{ボリューム統計行, 透過率行};
pub use row::{代表行, 再現性行, 検証行, 統計行};

use crate::acceptance::{検収エラー, 終了時報告};

pub struct 報告 {
    pub 検証: 検証行,
    pub 再現性: 再現性行,
    pub 統計一覧: Vec<統計行>,
    pub 代表一覧: Vec<代表行>,
    pub 透過率一覧: Vec<透過率行>,
    pub ボリューム統計: ボリューム統計行,
}

pub fn 報告を取り出す(報告: &終了時報告) -> Result<報告, 検収エラー> {
    Ok(報告 {
        検証: row::検証を読む(&報告.見出しの1行(&heading::検証層の見出し)?)?,
        再現性: row::再現性を読む(&報告.見出しの1行(&heading::再現性の見出し)?)?,
        統計一覧: 統計一覧を読む(報告)?,
        代表一覧: 代表一覧を読む(報告)?,
        透過率一覧: 透過率一覧を読む(報告)?,
        ボリューム統計: aerial_row::ボリューム統計を読む(&報告.見出しの1行(&heading::空中遠近の統計の見出し)?)?,
    })
}

/// 平面のベイク済み画像3枚の統計。行が欠けても読み取りでは落とさず本数の判定へ渡す。
/// 3本でないことは判定の材料であって、読み取りの破れではない。
fn 統計一覧を読む(報告: &終了時報告) -> Result<Vec<統計行>, 検収エラー> {
    let mut 一覧 = Vec::new();
    for 見出し in &heading::平面の統計の見出し一覧 {
        for 行 in 報告.見出しで始まる行の一覧(見出し) {
            一覧.push(row::統計を読む(&行, 見出し)?);
        }
    }
    Ok(一覧)
}

fn 代表一覧を読む(報告: &終了時報告) -> Result<Vec<代表行>, 検収エラー> {
    let mut 一覧 = Vec::new();
    for 見出し in &heading::代表テクセルの見出し一覧 {
        for 行 in 報告.見出しで始まる行の一覧(見出し) {
            一覧.push(row::代表を読む(&行, 見出し)?);
        }
    }
    Ok(一覧)
}

fn 透過率一覧を読む(報告: &終了時報告) -> Result<Vec<透過率行>, 検収エラー> {
    let mut 一覧 = Vec::new();
    for 行 in 報告.見出しで始まる行の一覧(&heading::空中遠近の代表透過率の見出し) {
        一覧.push(aerial_row::透過率を読む(&行)?);
    }
    Ok(一覧)
}
