//! 代表テクセルと代表ボクセルの値がCPU正本と一致するかの検査と、その要約。
//! 受け取るのは切り出した報告、返すのは要約か理由付きの不合格である。
//!
//! 許容との比較をここが単独で持つのは、誤差の見方(中域は相対・ほぼ0の域は絶対・透過率は相対だけ)が
//! 量ごとに違い、その選び分けと不合格の説明文が1組だからである。件数を数える検査とは判定の材料が重ならない。

use super::super::parse::{代表行, 報告};
use super::super::thresholds::{空中遠近の透過率の相対許容, 見出しから許容を選ぶ};

/// 一致の検査が観測した誤差の要約。3つとも代表の比較からしか出ないため、この工程が所有する。
pub struct 判定結果 {
    pub 代表テクセル数: usize,
    pub 最大相対誤差: f64,
    pub 最大絶対誤差: f64,
}

/// 代表ボクセルの代表透過率がCPU正本と一致すること。透過率は1に近い値を取るため相対誤差だけで見る。
pub(super) fn 代表透過率を検査する(報告: &報告) -> Result<(), String> {
    if 報告.透過率一覧.is_empty() {
        return Err("空中遠近の代表透過率の行が1つも無い".to_string());
    }
    for 行 in &報告.透過率一覧 {
        let 相対誤差 = (行.期待 - 行.実測).abs() / 行.期待.abs().max(f64::MIN_POSITIVE);
        if 相対誤差 > 空中遠近の透過率の相対許容 {
            return Err(format!(
                "空中遠近の横{}縦{}奥{}の代表透過率がCPU正本と食い違う(期待{:.9} 実測{:.9} 相対誤差{相対誤差:.3e} 許容{:.3e})",
                行.横, 行.縦, 行.奥, 行.期待, 行.実測, 空中遠近の透過率の相対許容
            ));
        }
    }
    Ok(())
}

/// 代表テクセルがCPU正本と一致すること。中域は相対誤差、ほぼ0の域は絶対誤差で見る。
pub(super) fn 代表テクセルを検査する(報告: &報告) -> Result<判定結果, String> {
    if 報告.代表一覧.is_empty() {
        return Err("代表テクセルの行が1つも無い".to_string());
    }
    let mut 最大相対誤差 = 0.0_f64;
    let mut 最大絶対誤差 = 0.0_f64;
    for 代表 in &報告.代表一覧 {
        let 許容 = 見出しから許容を選ぶ(&代表.見出し, 代表.縦);
        for (成分, (期待, 実測)) in 代表.期待.into_iter().zip(代表.実測).enumerate() {
            let 絶対誤差 = (期待 - 実測).abs();
            最大絶対誤差 = 最大絶対誤差.max(絶対誤差);
            if !許容.相対で見るか(期待) {
                if 絶対誤差 > 許容.絶対許容 {
                    return Err(誤差の説明(代表, 成分, 期待, 実測, "絶対", 絶対誤差, 許容.絶対許容));
                }
                continue;
            }
            let 相対誤差 = 絶対誤差 / 期待.abs();
            最大相対誤差 = 最大相対誤差.max(相対誤差);
            if 相対誤差 > 許容.相対許容 {
                return Err(誤差の説明(代表, 成分, 期待, 実測, "相対", 相対誤差, 許容.相対許容));
            }
        }
    }
    Ok(判定結果 {
        代表テクセル数: 報告.代表一覧.len(),
        最大相対誤差,
        最大絶対誤差,
    })
}

fn 誤差の説明(代表: &代表行, 成分: usize, 期待: f64, 実測: f64, 種別: &str, 誤差: f64, 許容: f64) -> String {
    let 名前 = ["赤", "緑", "青"].get(成分).copied().unwrap_or("不明");
    format!(
        "{}の横{}縦{}の{名前}がCPU正本と食い違う(期待{期待:.9} 実測{実測:.9} {種別}誤差{誤差:.3e} 許容{許容:.3e})",
        代表.見出し, 代表.横, 代表.縦
    )
}
