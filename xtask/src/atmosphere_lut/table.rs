//! 判定に使った値を人が読む表として出す。受け取るのは切り出した報告、返り値は無い。
//! 合否だけでなく実測の誤差を毎回出すのは、閾値の余裕がどれだけ残っているかを見えるようにするためである。
//!
//! 相対誤差の欄に載せるのは判定が相対で見た成分だけである。ほぼ0の成分まで混ぜると、
//! 半精度の刻みに埋もれた値の相対誤差が1に近づき、表だけを見た人が不合格と読み違える。

use super::parse::{代表行, 報告};
use super::thresholds::見出しから許容を選ぶ;

pub fn 表を出す(報告: &報告) {
    println!("[xtask] 大気LUT統計");
    for 統計 in &報告.統計一覧 {
        println!(
            "  {:<12} テクセル数{:>6} 非有限{} 負{} 一超え{} 予約が非零{} 最大{:.6}",
            統計.見出し, 統計.テクセル数, 統計.非有限, 統計.負, 統計.一超え, 統計.予約が非零, 統計.最大
        );
    }
    println!("[xtask] 代表テクセルのCPU正本との差(相対は判定が相対で見た成分だけ、絶対は全成分)");
    for 代表 in &報告.代表一覧 {
        println!(
            "  {:<12} 横{:>3} 縦{:>3} 期待({:.6}, {:.6}, {:.6}) 実測({:.6}, {:.6}, {:.6}) 相対{:.3e} 絶対{:.3e}",
            代表.見出し,
            代表.横,
            代表.縦,
            代表.期待[0],
            代表.期待[1],
            代表.期待[2],
            代表.実測[0],
            代表.実測[1],
            代表.実測[2],
            最大相対誤差(代表),
            最大絶対誤差(代表)
        );
    }
}

fn 最大相対誤差(代表: &代表行) -> f64 {
    let 許容 = 見出しから許容を選ぶ(&代表.見出し);
    代表
        .期待
        .into_iter()
        .zip(代表.実測)
        .filter(|(期待, _)| 許容.相対で見るか(*期待))
        .map(|(期待, 実測)| (期待 - 実測).abs() / 期待.abs())
        .fold(0.0, f64::max)
}

fn 最大絶対誤差(代表: &代表行) -> f64 {
    代表
        .期待
        .into_iter()
        .zip(代表.実測)
        .map(|(期待, 実測)| (期待 - 実測).abs())
        .fold(0.0, f64::max)
}
