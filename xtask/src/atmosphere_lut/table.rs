//! 判定に使った値を人が読む表として出す。受け取るのは切り出した報告、返り値は無い。
//! 合否だけでなく実測の誤差を毎回出すのは、閾値の余裕がどれだけ残っているかを見えるようにするためである。
//!
//! 相対誤差の欄に載せるのは判定が相対で見た成分だけである。ほぼ0の成分まで混ぜると、
//! 半精度の刻みに埋もれた値の相対誤差が1に近づき、表だけを見た人が不合格と読み違える。

use super::parse::{代表行, 報告};
use super::tolerance_choice::見出しから許容を選ぶ;

pub fn 表を出す(報告: &報告) {
    println!("[xtask] 大気のベイク済み画像統計");
    for 統計 in &報告.統計一覧 {
        println!(
            "  {:<12} テクセル数{:>6} 非有限{} 負{} 一超え{} 予約が非零{} 最大{:.6}",
            統計.見出し, 統計.テクセル数, 統計.非有限, 統計.負, 統計.一超え, 統計.予約が非零, 統計.最大
        );
    }
    let 統計 = &報告.ボリューム統計;
    println!(
        "  {:<12} ボクセル数{:>6} 非有限{} 負{} 透過率が値域外{} 最大{:.6}",
        "空中遠近統計", 統計.ボクセル数, 統計.非有限, 統計.負, 統計.透過率が値域外, 統計.最大
    );
    println!("[xtask] 代表テクセルのCPU正本との差(相対は判定が相対で見た成分だけ、絶対は全成分)");
    for 代表 in &報告.代表一覧 {
        println!(
            "  {:<12} 横{:>3} 縦{:>3} 期待({:.6}, {:.6}, {:.6}) 実測({:.6}, {:.6}, {:.6}) 相対{:.3e} 絶対{:.3e}",
            代表.見出し,
            代表.横,
            代表.縦,
            代表.期待[0],
            代表.期待[1],
            代表.期待[2],
            代表.実測[0],
            代表.実測[1],
            代表.実測[2],
            最大相対誤差(代表),
            最大絶対誤差(代表)
        );
    }
    透過率の表を出す(報告);
}

/// 空中遠近の代表透過率の期待と実測。散乱の表と別に出すのは、判定が許容の見方を分けているためである。
fn 透過率の表を出す(報告: &報告) {
    println!("[xtask] 空中遠近の代表透過率のCPU正本との差");
    for 行 in &報告.透過率一覧 {
        let 相対誤差 = (行.期待 - 行.実測).abs() / 行.期待.abs().max(f64::MIN_POSITIVE);
        println!(
            "  横{:>3} 縦{:>3} 奥{:>3} 期待{:.9} 実測{:.9} 相対{相対誤差:.3e}",
            行.横, 行.縦, 行.奥, 行.期待, 行.実測
        );
    }
}

fn 最大相対誤差(代表: &代表行) -> f64 {
    let 許容 = 見出しから許容を選ぶ(&代表.見出し, 代表.縦);
    代表
        .期待
        .into_iter()
        .zip(代表.実測)
        .filter(|(期待, _)| 許容.相対で見るか(*期待))
        .map(|(期待, 実測)| (期待 - 実測).abs() / 期待.abs())
        .fold(0.0, f64::max)
}

fn 最大絶対誤差(代表: &代表行) -> f64 {
    代表
        .期待
        .into_iter()
        .zip(代表.実測)
        .map(|(期待, 実測)| (期待 - 実測).abs())
        .fold(0.0, f64::max)
}
