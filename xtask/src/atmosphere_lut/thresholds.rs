//! 判定の閾値と、成分ごとにどちらの誤差で見るかの振り分け。判定と表示が同じ基準を読むため、
//! 表に出る数字と合否の判断が食い違わない。
//!
//! 閾値は2026-07-30の実測から決めた。GPUはR16G16B16A16_SFLOATへ書くため、半精度の仮数11ビットぶんの
//! 丸めが必ず入る。丸めだけで相対4.9e-4まで動くうえ、多重散乱は20区間64方向の積算をf32で行うためさらに誤差が積もる。
//! 実測の最大は透過率が相対7.8e-4(値0.00848の緑)、多重散乱が相対1.22e-3(値0.00391の赤)であり、
//! 閾値はそれぞれ2.0e-3(2.5倍の余裕)と5.0e-3(4.1倍の余裕)に置く。
//!
//! ほぼ0の域を絶対誤差で見るのは、半精度の非正規化数の刻みが6e-8であり、それより小さい期待値は必ず0へ落ちるためである。
//! 実測の最大は絶対6.5e-8(値4.05e-5の青)であり、閾値1.0e-6は15倍の余裕を持つ。

/// LUTの種類ごとの許容。相対で見る下限を分けるのは、透過率が0から1、多重散乱が0から0.04と桁が違うためである。
pub struct 許容 {
    pub 相対判定の下限: f64,
    pub 相対許容: f64,
    pub 絶対許容: f64,
}

const 透過率の許容: 許容 = 許容 {
    相対判定の下限: 1.0e-3,
    相対許容: 2.0e-3,
    絶対許容: 1.0e-6,
};

const 多重散乱の許容: 許容 = 許容 {
    相対判定の下限: 1.0e-4,
    相対許容: 5.0e-3,
    絶対許容: 1.0e-6,
};

/// スカイビューの許容。2026-07-30の実測の最大は相対4.12e-3(横96縦54の青・値0.02524)であり、閾値1.0e-2は2.4倍の余裕を持つ。
/// 多重散乱より緩いのは、スカイビューが30区間の積分の中で透過率LUTと多重散乱LUTの2枚を補間で引き、
/// 半精度で丸めた入力の誤差が積分を通って積もるためである。相対判定の下限を多重散乱と揃えるのは、
/// どちらも太陽の放射照度を1としたときの伝達率であり、値の桁が同じだからである。
///
/// 誤差の最大が地平線の直下(縦54)へ移り、丸めだけの水準(相対4.9e-4)の8倍まで伸びたのは、地表の遮蔽判定が
/// 標本点の位置の真偽値であるためである。地平線をかすめる視線の標本点は遮蔽球の境界に沿って並ぶため、
/// 惑星中心から測った半径の刻みが0.5メートルほどになるGPUのf32と、CPUのf64で真偽が反転する標本が混じる。
/// 1つ反転すると30区間のうち1区間ぶんの一次散乱が丸ごと動き、それが実測の4.12e-3に当たる。
/// 閾値を反転1つぶんの2.4倍に取るのは、機種差で境界付近の標本がもう1つ反転しても検収が落ちないためである。
/// 写しの誤りは値そのものを数割動かすため、この幅でも落とせる。片側だけを是正前へ戻した負の対照では、
/// 横0縦53の赤が相対3.11e-1で落ちた(閾値の31倍)。
const スカイビューの許容: 許容 = 許容 {
    相対判定の下限: 1.0e-4,
    相対許容: 1.0e-2,
    絶対許容: 1.0e-6,
};

pub fn 見出しから許容を選ぶ(見出し: &str) -> 許容 {
    match 見出し {
        "多重散乱代表" => 多重散乱の許容,
        "スカイビュー代表" => スカイビューの許容,
        _ => 透過率の許容,
    }
}

impl 許容 {
    /// その期待値を相対誤差で見るか。下限を下回る成分は半精度の刻みに埋もれるため絶対誤差で見る。
    pub fn 相対で見るか(&self, 期待: f64) -> bool {
        期待.abs() >= self.相対判定の下限
    }
}
