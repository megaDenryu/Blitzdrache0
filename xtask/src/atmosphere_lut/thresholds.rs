//! 判定の閾値と、成分ごとにどちらの誤差で見るかの振り分け。判定と表示が同じ基準を読むため、
//! 表に出る数字と合否の判断が食い違わない。
//!
//! 閾値は2026-07-30の実測から決めた。GPUはR16G16B16A16_SFLOATへ書くため、半精度の仮数11ビットぶんの
//! 丸めが必ず入る。丸めだけで相対4.9e-4まで動くうえ、多重散乱は20区間64方向の積算をf32で行うためさらに誤差が積もる。
//! 実測の最大は透過率が相対7.8e-4(値0.00848の緑)、多重散乱が相対1.22e-3(値0.00391の赤)であり、
//! 閾値はそれぞれ2.0e-3(2.5倍の余裕)と5.0e-3(4.1倍の余裕)に置く。
//!
//! ほぼ0の域を絶対誤差で見るのは、半精度の非正規化数の刻みが6e-8であり、それより小さい期待値は必ず0へ落ちるためである。
//! 実測の最大は絶対6.5e-8(値4.05e-5の青)であり、閾値1.0e-6は15倍の余裕を持つ。

/// ベイク済み画像の種類ごとの許容。相対で見る下限を分けるのは、透過率が0から1、多重散乱が0から0.04と桁が違うためである。
pub struct 許容 {
    pub 相対判定の下限: f64,
    pub 相対許容: f64,
    pub 絶対許容: f64,
}

pub(super) const 透過率の許容: 許容 = 許容 {
    相対判定の下限: 1.0e-3,
    相対許容: 2.0e-3,
    絶対許容: 1.0e-6,
};

pub(super) const 多重散乱の許容: 許容 = 許容 {
    相対判定の下限: 1.0e-4,
    相対許容: 5.0e-3,
    絶対許容: 1.0e-6,
};

// スカイビューの許容は縦位置で2つに分ける。多重散乱より緩いのは、スカイビューが30区間の積分の中で
// 透過率のベイク済み画像と多重散乱のベイク済み画像の2枚を補間で参照し、半精度で丸めた入力の誤差が
// 積分を通って積もるためである。相対判定の下限を多重散乱と揃えるのは、どちらも太陽の放射照度を1と
// したときの伝達率であり、値の桁が同じだからである。テクセル数20736(横192・縦108)の中央53.5を
// またぐ縦53・54だけ、地表の遮蔽判定の真偽反転で誤差が跳ねるため、この2行だけ別枠の緩い許容を持つ。

/// スカイビューの許容(縦53・54を除く)。丸め由来の積算どまりで、遮蔽判定の真偽反転を伴わない。
/// 2026-07-31の実測の最大は相対1.380e-3(横0縦27の緑)であり、閾値3.3e-3は2.4倍の余裕を持つ。
/// 負の対照: 閾値を実測未満の1.0e-3へ一時的に下げて実行すると、判定は最初に走査した横0縦0の青
/// (相対1.066e-3)で「スカイビュー代表の横0縦0の青がCPU正本と食い違う(許容1.000e-3)」として
/// 不合格になった。締めた側の許容が実際に効いていることを確認できた。
pub(super) const スカイビューの許容: 許容 = 許容 {
    相対判定の下限: 1.0e-4,
    相対許容: 3.3e-3,
    絶対許容: 1.0e-6,
};

/// スカイビューの許容(縦53・54のみ、地平線近傍)。2026-07-30の実測の最大は相対4.12e-3
/// (横96縦54の青・値0.02524)であり、閾値1.0e-2は2.4倍の余裕を持つ。誤差が丸めだけの水準
/// (相対4.9e-4)の8倍まで伸びるのは、地表の遮蔽判定が標本点の位置の真偽値であるためである。
/// 地平線をかすめる視線の標本点は遮蔽球の境界に沿って並ぶため、惑星中心から測った半径の刻みが
/// 0.5メートルほどになるGPUのf32と、CPUのf64で真偽が反転する標本が混じる。1つ反転すると30区間の
/// うち1区間ぶんの一次散乱が丸ごと動き、それが実測の4.12e-3に当たる。閾値を反転1つぶんの2.4倍に
/// 取るのは、機種差で境界付近の標本がもう1つ反転しても検収が落ちないためである。写しの誤りは
/// 値そのものを数割動かすため、この幅でも落とせる。片側だけを是正前へ戻した負の対照では、
/// 横0縦53の赤が相対3.11e-1で落ちた(閾値の31倍)。
pub(super) const スカイビュー地平線近傍の許容: 許容 = 許容 {
    相対判定の下限: 1.0e-4,
    相対許容: 1.0e-2,
    絶対許容: 1.0e-6,
};

/// 空中遠近の散乱の許容。スカイビューの地平線近傍と同じ1.0e-2に置く。同じ2枚の表を半精度で丸めた入力から
/// 同じ区間の式で積むため、誤差の出どころがスカイビューと同じである。加えて経路が数百メートルと短く積む
/// 区間の数が最大でも62であるため、誤差の積もりはスカイビュー(30区間で経路が数十キロメートル)より小さい。
/// 本タスクでは空中遠近の代表テクセルの縦位置と地表遮蔽の関係を未調査のため、締める側の変更対象から外す。
/// 相対判定の下限もスカイビューと揃える。どちらも太陽の放射照度を1としたときの伝達率であり値の桁が同じである。
pub(super) const 空中遠近の許容: 許容 = 許容 {
    相対判定の下限: 1.0e-4,
    相対許容: 1.0e-2,
    絶対許容: 1.0e-6,
};

/// 代表透過率の相対許容。透過率は1に近い値を取り、半精度の刻みが1付近で相対4.9e-4であるため、その4倍を取る。
/// 散乱より厳しくできるのは、透過率が積分でなく消散の総和の指数であり、区間ごとの誤差が積もらないためである。
pub const 空中遠近の透過率の相対許容: f64 = 2.0e-3;

impl 許容 {
    /// その期待値を相対誤差で見るか。下限を下回る成分は半精度の刻みに埋もれるため絶対誤差で見る。
    pub fn 相対で見るか(&self, 期待: f64) -> bool {
        期待.abs() >= self.相対判定の下限
    }
}
