//! 大気LUTの読み戻し検査の判定。受け取るのは切り出した報告、返すのは合格か理由付きの不合格である。
//! 閾値とその実測根拠は`thresholds`が持ち、表示側も同じ基準を読む。

use super::parse::報告;
use super::thresholds::見出しから許容を選ぶ;

pub struct 判定結果 {
    pub 代表テクセル数: usize,
    pub 最大相対誤差: f64,
    pub 最大絶対誤差: f64,
}

pub fn 全項目を検査する(報告: &報告) -> Result<判定結果, String> {
    決定性を検査する(報告)?;
    統計を検査する(報告)?;
    代表テクセルを検査する(報告)
}

/// 同じ入力で2回焼いた結果が1ビットも違わないこと。決定性の契約そのものである。
fn 決定性を検査する(報告: &報告) -> Result<(), String> {
    let 不一致 = 報告.再現性.透過率の不一致 + 報告.再現性.多重散乱の不一致 + 報告.再現性.スカイビューの不一致;
    if 不一致 != 0 {
        return Err(format!(
            "同じ入力を2回焼いた結果が一致しない(透過率{}テクセル・多重散乱{}テクセル・スカイビュー{}テクセル)",
            報告.再現性.透過率の不一致, 報告.再現性.多重散乱の不一致, 報告.再現性.スカイビューの不一致
        ));
    }
    Ok(())
}

/// 全要素の有限性と非負、透過率の上限、予約成分が0であること。
fn 統計を検査する(報告: &報告) -> Result<(), String> {
    if 報告.統計一覧.len() != 3 {
        return Err(format!("統計の行が3本でなく{}本である", 報告.統計一覧.len()));
    }
    for 統計 in &報告.統計一覧 {
        let 見出し = &統計.見出し;
        if 統計.テクセル数 == 0 {
            return Err(format!("{見出し}のテクセル数が0である"));
        }
        if 統計.非有限 != 0 || 統計.負 != 0 {
            return Err(format!("{見出し}に非有限{}件・負{}件がある", 統計.非有限, 統計.負));
        }
        if 統計.予約が非零 != 0 {
            return Err(format!("{見出し}の予約成分が0でないテクセルが{}件ある", 統計.予約が非零));
        }
        if 見出し == "透過率統計" && 統計.一超え != 0 {
            return Err(format!("透過率が1を超えたテクセルが{}件ある", 統計.一超え));
        }
    }
    Ok(())
}

/// 代表テクセルがCPU正本と一致すること。中域は相対誤差、ほぼ0の域は絶対誤差で見る。
fn 代表テクセルを検査する(報告: &報告) -> Result<判定結果, String> {
    if 報告.代表一覧.is_empty() {
        return Err("代表テクセルの行が1つも無い".to_string());
    }
    let mut 最大相対誤差 = 0.0_f64;
    let mut 最大絶対誤差 = 0.0_f64;
    for 代表 in &報告.代表一覧 {
        let 許容 = 見出しから許容を選ぶ(&代表.見出し);
        for (成分, (期待, 実測)) in 代表.期待.into_iter().zip(代表.実測).enumerate() {
            let 絶対誤差 = (期待 - 実測).abs();
            最大絶対誤差 = 最大絶対誤差.max(絶対誤差);
            if !許容.相対で見るか(期待) {
                if 絶対誤差 > 許容.絶対許容 {
                    return Err(誤差の説明(代表, 成分, 期待, 実測, "絶対", 絶対誤差, 許容.絶対許容));
                }
                continue;
            }
            let 相対誤差 = 絶対誤差 / 期待.abs();
            最大相対誤差 = 最大相対誤差.max(相対誤差);
            if 相対誤差 > 許容.相対許容 {
                return Err(誤差の説明(代表, 成分, 期待, 実測, "相対", 相対誤差, 許容.相対許容));
            }
        }
    }
    Ok(判定結果 {
        代表テクセル数: 報告.代表一覧.len(),
        最大相対誤差,
        最大絶対誤差,
    })
}

fn 誤差の説明(代表: &super::parse::代表行, 成分: usize, 期待: f64, 実測: f64, 種別: &str, 誤差: f64, 許容: f64) -> String {
    let 名前 = ["赤", "緑", "青"].get(成分).copied().unwrap_or("不明");
    format!(
        "{}の横{}縦{}の{名前}がCPU正本と食い違う(期待{期待:.9} 実測{実測:.9} {種別}誤差{誤差:.3e} 許容{許容:.3e})",
        代表.見出し, 代表.横, 代表.縦
    )
}
