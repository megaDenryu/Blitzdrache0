//! 大気のベイク済み画像の読み戻し検査の判定。受け取るのは切り出した報告、返すのは合格か理由付きの不合格である。
//!
//! ここが持つのは「壊れた値が1つも無いこと」を件数で見る検査(決定性・統計・ボリューム統計)である。
//! CPU正本との誤差を許容と比べる検査は`representative_match`が持ち、閾値とその実測根拠は`thresholds`が持つ。

mod representative_match;

use representative_match::{代表テクセルを検査する, 代表透過率を検査する};

pub use representative_match::判定結果;

use super::heading;
use super::parse::{報告, 統計行};
use crate::acceptance::{判定の名前, 判定の破れ};
use crate::report_heading::報告の見出し;

/// 平面のベイク済み画像の統計の行が並ぶ本数。透過率・多重散乱・スカイビューの3枚ぶんである。
const 平面の統計の行数: usize = 3;

const 平面の統計の行の本数: 判定の名前 = 判定の名前::定数から生成する("平面のベイク済み画像の統計の行の本数");
const 空中遠近のボクセル: 判定の名前 = 判定の名前::定数から生成する("空中遠近統計が数えたボクセル");

pub fn 全項目を検査する(報告: &報告) -> Result<判定結果, 判定の破れ> {
    決定性を検査する(報告)?;
    統計を検査する(報告)?;
    ボリューム統計を検査する(報告)?;
    代表透過率を検査する(報告)?;
    代表テクセルを検査する(報告)
}

/// 同じ入力で2回焼いた結果が1ビットも違わないこと。決定性の契約そのものである。
fn 決定性を検査する(報告: &報告) -> Result<(), 判定の破れ> {
    let 再現性 = &報告.再現性;
    let 不一致 = 再現性.透過率の不一致 + 再現性.多重散乱の不一致 + 再現性.スカイビューの不一致 + 再現性.空中遠近の不一致;
    let 判定名 = 判定の名前::組み立てた綴りから生成する(format!(
        "同じ入力を2回焼いた結果の不一致(透過率{}・多重散乱{}・スカイビュー{}・空中遠近{})",
        再現性.透過率の不一致, 再現性.多重散乱の不一致, 再現性.スカイビューの不一致, 再現性.空中遠近の不一致
    ));
    判定名.零件であることを課す(不一致)
}

/// 空中遠近ボリュームの全ボクセルの有限性と非負、代表透過率が0以上1以下であること。
fn ボリューム統計を検査する(報告: &報告) -> Result<(), 判定の破れ> {
    let 統計 = &報告.ボリューム統計;
    if 統計.ボクセル数 == 0 {
        return Err(空中遠近のボクセル.あるはずのものが無い破れ());
    }
    let 見出し = &heading::空中遠近の統計の見出し;
    壊れた値の判定名(見出し, "非有限のボクセル").零件であることを課す(統計.非有限)?;
    壊れた値の判定名(見出し, "負のボクセル").零件であることを課す(統計.負)?;
    壊れた値の判定名(見出し, "代表透過率が0以上1以下を外れたボクセル").零件であることを課す(統計.透過率が値域外)
}

/// 全要素の有限性と非負、透過率の上限、予約成分が0であること。
fn 統計を検査する(報告: &報告) -> Result<(), 判定の破れ> {
    平面の統計の行の本数.一致を課す(報告.統計一覧.len(), 平面の統計の行数)?;
    for 統計 in &報告.統計一覧 {
        一枚の統計を検査する(統計)?;
    }
    Ok(())
}

fn 一枚の統計を検査する(統計: &統計行) -> Result<(), 判定の破れ> {
    let 見出し = &統計.見出し;
    if 統計.テクセル数 == 0 {
        return Err(テクセルの判定名(見出し).あるはずのものが無い破れ());
    }
    壊れた値の判定名(見出し, "非有限のテクセル").零件であることを課す(統計.非有限)?;
    壊れた値の判定名(見出し, "負のテクセル").零件であることを課す(統計.負)?;
    壊れた値の判定名(見出し, "予約成分が0でないテクセル").零件であることを課す(統計.予約が非零)?;
    if 見出し != &heading::透過率の統計の見出し {
        return Ok(());
    }
    壊れた値の判定名(見出し, "1を超えたテクセル").零件であることを課す(統計.一超え)
}

fn テクセルの判定名(見出し: &報告の見出し) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{見出し}が数えたテクセル"))
}

fn 壊れた値の判定名(見出し: &報告の見出し, 数える対象: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{見出し}の{数える対象}"))
}
