//! 大気のベイク済み画像の読み戻し検査の判定。受け取るのは切り出した報告、返すのは合格か理由付きの不合格である。
//!
//! ここが持つのは「壊れた値が1つも無いこと」を件数で見る検査(決定性・統計・ボリューム統計)である。
//! CPU正本との誤差を許容と比べる検査は`representative_match`が持ち、閾値とその実測根拠は`thresholds`が持つ。

mod representative_match;

use representative_match::{代表テクセルを検査する, 代表透過率を検査する};

pub use representative_match::判定結果;

use super::parse::報告;

pub fn 全項目を検査する(報告: &報告) -> Result<判定結果, String> {
    決定性を検査する(報告)?;
    統計を検査する(報告)?;
    ボリューム統計を検査する(報告)?;
    代表透過率を検査する(報告)?;
    代表テクセルを検査する(報告)
}

/// 同じ入力で2回焼いた結果が1ビットも違わないこと。決定性の契約そのものである。
fn 決定性を検査する(報告: &報告) -> Result<(), String> {
    let 再現性 = &報告.再現性;
    let 不一致 = 再現性.透過率の不一致 + 再現性.多重散乱の不一致 + 再現性.スカイビューの不一致 + 再現性.空中遠近の不一致;
    if 不一致 != 0 {
        return Err(format!(
            "同じ入力を2回焼いた結果が一致しない(透過率{}・多重散乱{}・スカイビュー{}・空中遠近{})",
            再現性.透過率の不一致, 再現性.多重散乱の不一致, 再現性.スカイビューの不一致, 再現性.空中遠近の不一致
        ));
    }
    Ok(())
}

/// 空中遠近ボリュームの全ボクセルの有限性と非負、代表透過率が0以上1以下であること。
fn ボリューム統計を検査する(報告: &報告) -> Result<(), String> {
    let 統計 = &報告.ボリューム統計;
    if 統計.ボクセル数 == 0 {
        return Err("空中遠近統計のボクセル数が0である".to_string());
    }
    if 統計.非有限 != 0 || 統計.負 != 0 {
        return Err(format!("空中遠近に非有限{}件・負{}件がある", 統計.非有限, 統計.負));
    }
    if 統計.透過率が値域外 != 0 {
        return Err(format!("空中遠近の代表透過率が0以上1以下を外れたボクセルが{}件ある", 統計.透過率が値域外));
    }
    Ok(())
}

/// 全要素の有限性と非負、透過率の上限、予約成分が0であること。
fn 統計を検査する(報告: &報告) -> Result<(), String> {
    if 報告.統計一覧.len() != 3 {
        return Err(format!("平面のベイク済み画像の統計の行が3本でなく{}本である", 報告.統計一覧.len()));
    }
    for 統計 in &報告.統計一覧 {
        let 見出し = &統計.見出し;
        if 統計.テクセル数 == 0 {
            return Err(format!("{見出し}のテクセル数が0である"));
        }
        if 統計.非有限 != 0 || 統計.負 != 0 {
            return Err(format!("{見出し}に非有限{}件・負{}件がある", 統計.非有限, 統計.負));
        }
        if 統計.予約が非零 != 0 {
            return Err(format!("{見出し}の予約成分が0でないテクセルが{}件ある", 統計.予約が非零));
        }
        if 見出し == "透過率統計" && 統計.一超え != 0 {
            return Err(format!("透過率が1を超えたテクセルが{}件ある", 統計.一超え));
        }
    }
    Ok(())
}
