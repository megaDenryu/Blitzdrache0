//! 個体別LODの検収の判定。受け取るのは実行結果と計数、返すのは合否である。
//! 判定は4つに分かれる。同じ群の中で2段以上が同時に立つこと、段の違いが遠景の画素に現れて近景は変わらないこと、
//! ヒステリシス帯の内側の往復で段が振動しないこと、段が切り替わる実行でもGPU確保とディスク読込が動かないことである。

use super::pixel_check;
use crate::report_parse::計数報告;
use crate::vegetation_run::実行結果;

pub(super) struct 実行 {
    pub(super) 名前: String,
    pub(super) 画像: 実行結果,
    pub(super) 計数: 計数報告,
}

/// 同じ群の中で2つ以上の段が同時に非零であること。シーンとシャドウのどちらもこの形になり、
/// 発行数はその非空段数と一致する。シャドウ側の段別個体数の合計が候補数と等しいことも同時に見る。
/// この世界の15体は全体がライト視錐台の内側にあるため、シャドウ側が1体でも減ればライト視錐台の導出か
/// 範囲の設定が誤っている。
pub(super) fn 段が同時に立つことを検査する(実行: &実行) -> Result<Vec<u64>, String> {
    for (パス名, 発行) in [("シーン", &実行.計数.シーン), ("シャドウ", &実行.計数.シャドウ)] {
        let 非零段数 = 発行.段別個体数.iter().filter(|個体数| **個体数 > 0).count();
        if 非零段数 < 2 {
            return Err(format!("{パス名}パスで2段以上が同時に立っていない: 段別個体数{:?}", 発行.段別個体数));
        }
        if 発行.発行数 != u64::try_from(非零段数).unwrap_or(u64::MAX) {
            return Err(format!("{パス名}パスの発行数{}が非空段数{非零段数}と一致しない", 発行.発行数));
        }
    }
    let シャドウ合計: u64 = 実行.計数.シャドウ.段別個体数.iter().sum();
    if シャドウ合計 != 実行.計数.シャドウ.候補数 {
        return Err(format!(
            "シャドウパスが全個体を描いていない: 段別個体数の合計{シャドウ合計}、候補{}体",
            実行.計数.シャドウ.候補数
        ));
    }
    Ok(実行.計数.シーン.段別個体数.clone())
}

/// 段の選択を止めた実行と比べ、遠景の領域だけが変わり近景がバイト一致すること。
/// 段なしの実行は全個体を最詳細段で描くため、そちらだけは段が1つしか立たない。
pub(super) fn 段の違いが絵に出ることを検査する(
    段あり: &実行, 段なし: &実行
) -> Result<pixel_check::領域別画素数, String> {
    if 段なし.計数.シーン.段別個体数.iter().filter(|個体数| **個体数 > 0).count() != 1 {
        return Err(format!(
            "段の選択を止めた実行で2段以上が立っている: 段別個体数{:?}",
            段なし.計数.シーン.段別個体数
        ));
    }
    pixel_check::領域を比べる(&段あり.画像, &段なし.画像)
}

/// ヒステリシス帯の内側の往復では段が入れ替わらず、帯を超える往復では入れ替わること。
/// 後者が無いと、前者が「そもそも境界をまたいでいないだけ」でも通ってしまう。
pub(super) fn 段が振動しないことを検査する(帯の内側: &実行, 帯の外側: &実行) -> Result<(), String> {
    if 帯の内側.計数.段切替回数 != 0 {
        return Err(format!("ヒステリシス帯の内側の往復で段が{}回入れ替わった", 帯の内側.計数.段切替回数));
    }
    if 帯の外側.計数.段切替回数 == 0 {
        return Err("帯を超える往復でも段が入れ替わらない。帯の内側の判定が空振りである".to_string());
    }
    Ok(())
}

/// どの実行でもGPU確保の現在数が最大同時確保数と等しく、実行どうしでも同じであり、起動後のシーン読込が0件であること。
/// 段が切り替わってもディスクI/OもGPU確保も起こさないという不変条件をこの3つで示す。
pub(super) fn 確保と読込が動かないことを検査する(実行一覧: &[&実行]) -> Result<(), String> {
    let Some(基準) = 実行一覧.first() else {
        return Err("比べる実行が1つも無い".to_string());
    };
    for 実行 in 実行一覧 {
        if 実行.計数.現在確保数 != 実行.計数.最大同時確保数 {
            return Err(format!(
                "{}の実行でGPU確保数が途中で増減した: 現在{}、最大{}",
                実行.名前, 実行.計数.現在確保数, 実行.計数.最大同時確保数
            ));
        }
        if 実行.計数.現在確保数 != 基準.計数.現在確保数 {
            return Err(format!(
                "{}の実行のGPU確保数{}が{}の実行の{}と違う",
                実行.名前, 実行.計数.現在確保数, 基準.名前, 基準.計数.現在確保数
            ));
        }
        if 実行.計数.起動後シーン読込回数 != 0 {
            return Err(format!(
                "{}の実行で起動後に{}回のシーン読込が起きた",
                実行.名前, 実行.計数.起動後シーン読込回数
            ));
        }
        if 実行.計数.validation件数 != 0 {
            return Err(format!("{}の実行でvalidationが{}件発生した", 実行.名前, 実行.計数.validation件数));
        }
    }
    Ok(())
}
