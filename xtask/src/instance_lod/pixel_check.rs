//! 読み戻し画像を遠景と近景の2つの領域へ分けて比べる工程。受け取るのは段ありと段なしの2枚、
//! 返すのは遠景の領域の非背景画素数である。
//!
//! 領域の境目は`crates/blitz_asset_compiler/src/vegetation/lod_placement.rs`が並べた5本の弧の写り方で決まる。
//! 段1へ落ちる60メートルと68メートルの弧は画面の上端寄りに、段0のままの40・45・48.5メートルの弧は下側に写り、
//! その間に個体の掛からない帯がある。境目をその帯の中へ置く。
//! 背景色は左上隅の画素から取る。この世界には床が無く、個体の掛からない画素はすべて番兵背景色である。

use crate::acceptance::{画素の横位置, 画素の番号, 画素の縦位置, 読み戻し画像};

/// 段1へ落ちる弧が写る領域の下端。
const 遠景の下端: usize = 200;

/// 段0のままの弧が写る領域の上端。遠景の下端との間の帯には個体が掛からない。
const 近景の上端: usize = 220;

pub(super) struct 領域別画素数 {
    pub(super) 遠景の段あり: u64,
    pub(super) 遠景の段なし: u64,
}

pub(super) fn 領域を比べる(段あり: &読み戻し画像, 段なし: &読み戻し画像) -> Result<領域別画素数, String> {
    寸法が同じかを確かめる(段あり, 段なし)?;
    let 遠景の段あり = 非背景画素を数える(段あり, 0, 遠景の下端);
    let 遠景の段なし = 非背景画素を数える(段なし, 0, 遠景の下端);
    // 粗い段の直方体は最詳細段より細く低いため、覆う画素は半分よりはっきり少なくなる。
    if 遠景の段あり * 2 >= 遠景の段なし {
        return Err(format!(
            "遠景の個体が粗い段になっていない: 段ありで{遠景の段あり}画素、段なしで{遠景の段なし}画素"
        ));
    }
    if 段あり.行以降のバイト列(画素の縦位置::生成する(近景の上端)) != 段なし.行以降のバイト列(画素の縦位置::生成する(近景の上端))
    {
        return Err("近景の領域が段の選択の有無で変わった".to_string());
    }
    Ok(領域別画素数 {
        遠景の段あり, 遠景の段なし
    })
}

fn 寸法が同じかを確かめる(左: &読み戻し画像, 右: &読み戻し画像) -> Result<(), String> {
    if !左.寸法が同じか(右) {
        return Err(format!("2枚の読み戻し画像の寸法が違う: {}と{}", 左.寸法の綴り(), 右.寸法の綴り()));
    }
    if 右.高さ().画素数() <= 近景の上端 {
        return Err(format!("読み戻し画像の高さ{}が近景の上端{近景の上端}に足りない", 右.高さ().画素数()));
    }
    Ok(())
}

/// 左上隅の画素と違う色の画素を数える。この世界には床が無いため、個体の掛からない画素はすべて左上隅と同じ番兵背景色である。
fn 非背景画素を数える(画像: &読み戻し画像, y開始: usize, y終端: usize) -> u64 {
    let 背景 = 画像.番号の画素(画素の番号::生成する(0));
    let mut 件数 = 0u64;
    for y in y開始..y終端.min(画像.高さ().画素数()) {
        for x in 0..画像.幅().画素数() {
            if 画像.座標の画素(画素の横位置::生成する(x), 画素の縦位置::生成する(y)) != 背景 {
                件数 += 1;
            }
        }
    }
    件数
}
