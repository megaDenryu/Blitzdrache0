//! 読み戻し画像を遠景と近景の2つの領域へ分けて比べる工程。受け取るのは段ありと段なしの2枚、
//! 返すのは遠景の領域の非背景画素数である。
//!
//! 領域の境目は`crates/blitz_asset_compiler/src/vegetation/lod_placement.rs`が並べた5本の弧の写り方で決まる。
//! 段1へ落ちる60メートルと68メートルの弧は画面の上端寄りに、段0のままの40・45・48.5メートルの弧は下側に写り、
//! その間に個体の掛からない帯がある。境目をその帯の中へ置く。
//! 背景色は左上隅の画素から取る。この世界には床が無く、個体の掛からない画素はすべて番兵背景色である。

use crate::acceptance::{判定の名前, 判定の破れ, 画素の横位置, 画素の番号, 画素の縦位置, 読み戻し画像};

/// 段1へ落ちる弧が写る領域の下端。
const 遠景の下端: usize = 200;

/// 段0のままの弧が写る領域の上端。遠景の下端との間の帯には個体が掛からない。
const 近景の上端: usize = 220;

const 近景の領域のバイト長: 判定の名前 = 判定の名前::定数から生成する("近景の領域のバイト長(段の選択の有無で一致するはずである)");
const 近景で違ったバイト: 判定の名前 = 判定の名前::定数から生成する("近景の領域が段の選択の有無で違ったバイト");

pub(super) struct 領域別画素数 {
    pub(super) 遠景の段あり: u64,
    pub(super) 遠景の段なし: u64,
}

pub(super) fn 領域を比べる(段あり: &読み戻し画像, 段なし: &読み戻し画像) -> Result<領域別画素数, 判定の破れ> {
    寸法が同じかを確かめる(段あり, 段なし)?;
    let 遠景の段あり = 非背景画素を数える(段あり, 0, 遠景の下端);
    let 遠景の段なし = 非背景画素を数える(段なし, 0, 遠景の下端);
    // 粗い段の直方体は最詳細段より細く低いため、覆う画素は半分よりはっきり少なくなる。
    遠景が粗い段であることの判定名(遠景の段あり, 遠景の段なし).真であることを課す(遠景の段あり * 2 < 遠景の段なし)?;
    let 上端 = 画素の縦位置::生成する(近景の上端);
    let (段ありの近景, 段なしの近景) = (段あり.行以降のバイト列(上端), 段なし.行以降のバイト列(上端));
    近景の領域のバイト長.一致を課す(段ありの近景.len(), 段なしの近景.len())?;
    let 違うバイト数 = 段ありの近景.iter().zip(段なしの近景).filter(|(左, 右)| 左 != 右).count();
    近景で違ったバイト.零件であることを課す(違うバイト数)?;
    Ok(領域別画素数 {
        遠景の段あり, 遠景の段なし
    })
}

fn 寸法が同じかを確かめる(左: &読み戻し画像, 右: &読み戻し画像) -> Result<(), 判定の破れ> {
    寸法が同じであることの判定名(左, 右).真であることを課す(左.寸法が同じか(右))?;
    近景の上端まで届く高さの判定名(右).真であることを課す(右.高さ().画素数() > 近景の上端)
}

/// 比べの形を下限でなく真偽で課すのは、この判定が近景の上端にちょうど等しい高さを破れの側へ置くためである。
/// 下限の口は等号を通すため、閾値をずらさずに置き換えることができない。
fn 近景の上端まで届く高さの判定名(画像: &読み戻し画像) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(
        format!("読み戻し画像の高さ{}が近景の上端{近景の上端}を超えること", 画像.高さ().画素数()),
    )
}

fn 寸法が同じであることの判定名(左: &読み戻し画像, 右: &読み戻し画像) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "2枚の読み戻し画像の寸法が同じであること({}と{})",
        左.寸法の綴り(),
        右.寸法の綴り()
    ))
}

/// 実測を綴りへ入れるのは、真偽で課す判定が比べた数を文面へ出せないためである。
fn 遠景が粗い段であることの判定名(遠景の段あり: u64, 遠景の段なし: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "遠景の個体が粗い段になっていること(段ありの{遠景の段あり}画素の2倍が段なしの{遠景の段なし}画素を下回ること)"
    ))
}

/// 左上隅の画素と違う色の画素を数える。この世界には床が無いため、個体の掛からない画素はすべて左上隅と同じ番兵背景色である。
fn 非背景画素を数える(画像: &読み戻し画像, y開始: usize, y終端: usize) -> u64 {
    let 背景 = 画像.番号の画素(画素の番号::生成する(0));
    let mut 件数 = 0u64;
    for y in y開始..y終端.min(画像.高さ().画素数()) {
        for x in 0..画像.幅().画素数() {
            if 画像.座標の画素(画素の横位置::生成する(x), 画素の縦位置::生成する(y)) != 背景 {
                件数 += 1;
            }
        }
    }
    件数
}
