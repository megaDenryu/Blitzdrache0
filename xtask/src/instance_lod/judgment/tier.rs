//! 段の立ち方についての判定。担当するのは、同じ群の中で2段以上が同時に立つこと、段の違いが遠景の画素に現れて
//! 近景は変わらないこと、ヒステリシス帯の内側の往復で段が振動しないことの3つを見ることである。
//! 資源が動かないことは`resource`が見る。

use super::実行;
use crate::acceptance::{判定の名前, 判定の破れ};
use crate::instance_lod::pixel_check;
use crate::report_parse::全パスを並べる;

const 二段以上が立った距離区分: 判定の名前 =
    判定の名前::定数から生成する("2段以上が同時に立った距離区分(距離区分ごとの段別発行が働いていれば1つ以上ある)");
const 影を落とす個体の数: 判定の名前 =
    判定の名前::定数から生成する("いずれかの距離区分へ影を落とす個体の数(影の範囲の内側の個体は落ちないはずである)");
const 帯の内側での段の入れ替わり: 判定の名前 = 判定の名前::定数から生成する("ヒステリシス帯の内側の往復で段が入れ替わった回数");
const 帯を超える往復での段の入れ替わり: 判定の名前 =
    判定の名前::定数から生成する("帯を超える往復での段の入れ替わり(これが無いと帯の内側の判定は空振りである)");

/// 同じ群の中で2つ以上の段が同時に非零であること。シーンと、影を落とす個体を持つ距離区分がこの形になり、発行数はその非空段数と
/// 一致する。いずれかの距離区分へ影を落とす個体が全個体であることも同時に見る。この世界の15体は全体が影の範囲の内側にあるため、
/// 距離区分の和集合の可視数が1体でも減れば距離区分のライト視錐台の導出か範囲の設定が誤っている。
pub(in crate::instance_lod) fn 段が同時に立つことを検査する(実行: &実行) -> Result<Vec<u64>, 判定の破れ> {
    crate::count_consistency::計数の整合を検査する(&実行.名前, &実行.計数)?;
    let mut 二段以上の距離区分数 = 0;
    for (パス名, 発行) in 全パスを並べる(&実行.計数) {
        let 非零段数 = 発行.段別個体数.iter().filter(|個体数| **個体数 > 0).count();
        パスの発行数の判定名(&パス名).一致を課す(発行.発行数, u64::try_from(非零段数).unwrap_or(u64::MAX))?;
        if パス名 == "シーンパス" {
            シーンパスで同時に立った段の判定名(&発行.段別個体数).下限を課す(非零段数, 2)?;
        } else if 非零段数 >= 2 {
            二段以上の距離区分数 += 1;
        }
    }
    if 二段以上の距離区分数 == 0 {
        return Err(二段以上が立った距離区分.あるはずのものが無い破れ());
    }
    let 可視個体の選別 = &実行.計数.可視個体の選別;
    影を落とす個体の数.一致を課す(可視個体の選別.距離区分の和集合の可視数, 可視個体の選別.候補数)?;
    Ok(実行.計数.シーン.段別個体数.clone())
}

/// 段の選択を止めた実行と比べ、遠景の領域だけが変わり近景がバイト一致すること。
/// 段なしの実行は全個体を最詳細段で描くため、そちらだけは段が1つしか立たない。
pub(in crate::instance_lod) fn 段の違いが絵に出ることを検査する(
    段あり: &実行,
    段なし: &実行,
) -> Result<pixel_check::領域別画素数, 判定の破れ> {
    let 段別 = &段なし.計数.シーン.段別個体数;
    段の選択を止めた実行で立った段の判定名(段別).一致を課す(段別.iter().filter(|個体数| **個体数 > 0).count(), 1)?;
    pixel_check::領域を比べる(&段あり.画像, &段なし.画像)
}

/// ヒステリシス帯の内側の往復では段が入れ替わらず、帯を超える往復では入れ替わること。
/// 後者が無いと、前者が「そもそも境界をまたいでいないだけ」でも通ってしまう。
pub(in crate::instance_lod) fn 段が振動しないことを検査する(
    帯の内側: &実行, 帯の外側: &実行
) -> Result<(), 判定の破れ> {
    帯の内側での段の入れ替わり.零件であることを課す(帯の内側.計数.段切替回数)?;
    if 帯の外側.計数.段切替回数 == 0 {
        return Err(帯を超える往復での段の入れ替わり.あるはずのものが無い破れ());
    }
    Ok(())
}

fn パスの発行数の判定名(パス名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{パス名}の発行数(非空段数と一致するはずである)"))
}

fn シーンパスで同時に立った段の判定名(段別個体数: &[u64]) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("シーンパスで同時に立った段の数(段別個体数{段別個体数:?})"))
}

fn 段の選択を止めた実行で立った段の判定名(段別個体数: &[u64]) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("段の選択を止めた実行で立った段の数(段別個体数{段別個体数:?})"))
}
