//! 段が切り替わっても資源が動かないことについての判定。担当するのは、どの実行でもGPU確保の現在数が最大同時確保数と
//! 等しく、実行どうしでも同じであり、起動後のシーン読込が0件であることを見ることである。
//! 段が切り替わってもディスクI/OもGPU確保も起こさないという不変条件をこの3つで示す。段の立ち方は`tier`が見る。

use super::実行;
use crate::acceptance::{判定の名前, 判定の破れ};

const 比べる実行: 判定の名前 = 判定の名前::定数から生成する("GPU確保数を突き合わせる実行");

pub(in crate::instance_lod) fn 確保と読込が動かないことを検査する(実行一覧: &[&実行]) -> Result<(), 判定の破れ> {
    let Some(基準) = 実行一覧.first() else {
        return Err(比べる実行.あるはずのものが無い破れ());
    };
    for 実行 in 実行一覧 {
        確保の現在数の判定名(&実行.名前).一致を課す(実行.計数.現在確保数, 実行.計数.最大同時確保数)?;
        実行どうしの確保数の判定名(&実行.名前, &基準.名前).一致を課す(実行.計数.現在確保数, 基準.計数.現在確保数)?;
        起動後のシーン読込の判定名(&実行.名前).零件であることを課す(実行.計数.起動後シーン読込回数)?;
        検証層の指摘の判定名(&実行.名前).零件であることを課す(実行.計数.validation件数)?;
    }
    Ok(())
}

fn 確保の現在数の判定名(実行名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{実行名}の実行のGPU確保の現在数(途中で増減していなければ最大同時確保数と一致する)"
    ))
}

fn 実行どうしの確保数の判定名(実行名: &str, 基準の実行名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{実行名}の実行のGPU確保数({基準の実行名}の実行と一致するはずである)"))
}

fn 起動後のシーン読込の判定名(実行名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{実行名}の実行で起きた起動後のシーン読込"))
}

fn 検証層の指摘の判定名(実行名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{実行名}の実行で出た検証層の指摘"))
}
