//! 植生の検証用世界を起こすための実行環境と起動指定。担当するのは、この世界の実行時アセットの置き場と、
//! 1条件ぶんの起動でどの選択肢を渡すかを1箇所で決めることである。
//!
//! 監視対象シェーダーはリポジトリ本体でなく一時コピーを渡す。植生の検証計画は書き換えを行わないが、
//! 監視の入口をリポジトリへ向けない規律を他の検証と揃える。
//!
//! この2つをここに置くのは、6つの入口が同じ世界を同じ置き場から起こすためである。入口ごとに置き場を書くと、
//! 片方だけがルートを変えたときに、絵を撮る入口と数を採る入口が別の世界を見ることになる。

use std::path::{Path, PathBuf};

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収エラー, 検収シーン名
};
use crate::verify::検証の出力ルート;

pub fn 植生世界の実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::パスから生成する(
            検証の出力ルート::既定().名前が指す置き場(crate::compile_assets::植生の世界の実行時形式の置き場),
        ),
        出力ディレクトリ,
    )
}

pub fn 植生世界の起動指定を組み立てる(
    シーン名: 検収シーン名,
    フレーム数: 描画フレーム数,
    シェーダー入口: &Path,
    追加の選択肢: &[&str],
) -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数)
        .選択肢をまとめて足す(追加の選択肢)
        .パスを値に持つ選択肢を足す("--shader-source", シェーダー入口)
}
