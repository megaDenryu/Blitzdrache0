//! 焼き上がった実行時形式のファイルを所有するモジュール。担当するのは、シーンの安定IDと実行時形式の
//! ファイル名の対応と、そのファイルの格納バイト数と中身を読むことである。
//!
//! 拡張子とパスの組み方をここだけが知るのは、読む側が出力ルートとシーンの綴りからファイル名を組み直すと、
//! 焼き付けの側が名前の付け方を変えたときに読む側だけが静かに別の場所を探すためである。
//!
//! どの世界をどの方針でどの出力ルートへ焼くかは`world_bake`が持つ。ここは焼き上がった後のファイルだけを見る。

use std::path::{Path, PathBuf};

use super::error::ブロック圧縮の検収エラー;
use crate::acceptance::検収シーン名;

/// 対照の板のシーンの綴り。この安定IDが実行時形式のファイル名にもなる。
const 対照の板のシーンの綴り: &str = "texture_compression";
/// DamagedHelmetのシーンの綴り。板の世界が任意アセットとして持つ既存の安定IDである。
const ヘルメットのシーンの綴り: &str = "helmet";

pub(super) const 対照の板のシーン名: 検収シーン名 = 検収シーン名::生成する(対照の板のシーンの綴り);
pub(super) const ヘルメットのシーン名: 検収シーン名 = 検収シーン名::生成する(ヘルメットのシーンの綴り);

/// 対照の板の実行時形式のバイト数。焼いた生成物の綴りを外へ出さないための口である。
pub(super) fn 対照の板の格納バイト数を読む(出力ルート: &Path) -> Result<u64, ブロック圧縮の検収エラー> {
    実行時形式のバイト数を読む(出力ルート, 対照の板のシーンの綴り)
}

/// DamagedHelmetの実行時形式のバイト数。
pub(super) fn ヘルメットの格納バイト数を読む(出力ルート: &Path) -> Result<u64, ブロック圧縮の検収エラー> {
    実行時形式のバイト数を読む(出力ルート, ヘルメットのシーンの綴り)
}

/// 対照の板の実行時形式そのもの。焼き付けの決定性を突き合わせる検査が読む。
pub(super) fn 対照の板の実行時形式を読む(出力ルート: &Path) -> Result<Vec<u8>, ブロック圧縮の検収エラー> {
    let パス = 実行時形式のパス(出力ルート, 対照の板のシーンの綴り);
    let 読み取り = std::fs::read(&パス);
    読み取り.map_err(|誤り| ブロック圧縮の検収エラー::実行時形式を読めなかった { パス, 誤り })
}

/// そのシーンの実行時形式1件のバイト数。テクスチャ格納バイト数の比を採るための実測値である。
fn 実行時形式のバイト数を読む(出力ルート: &Path, シーン名: &str) -> Result<u64, ブロック圧縮の検収エラー> {
    let パス = 実行時形式のパス(出力ルート, シーン名);
    let 読み取り = std::fs::metadata(&パス);
    let メタデータ =
        読み取り.map_err(|誤り| ブロック圧縮の検収エラー::実行時形式の大きさを読めなかった { パス, 誤り })?;
    Ok(メタデータ.len())
}

fn 実行時形式のパス(出力ルート: &Path, シーン名: &str) -> PathBuf {
    出力ルート.join(format!("{シーン名}.blitzasset"))
}
