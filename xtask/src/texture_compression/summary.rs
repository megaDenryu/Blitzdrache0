//! 検収の結果を人が読む1行へ組み立てる工程。担当するのは文言と数の並べ方だけであり、統計の求め方も判定値も持たない。
//!
//! 千分率で持っている平均を小数の見た目へ戻すのは報告の側の仕事である。統計の側で小数へ直すと、
//! 判定値との突き合わせに丸めが入る。

use super::difference::{度数分布の区分の下限, 画素の成分差の統計};

pub(super) fn 統計の行を作る(素材名: &str, 統計: &画素の成分差の統計) -> String {
    format!(
        "{素材名}は成分差の最大{}符号値・平均{}符号値・差のある画素{}/{}、度数分布{}",
        統計.最大,
        千分率を小数の見た目にする(統計.平均の千分率),
        統計.差のある画素数,
        統計.画素数,
        度数分布の行を作る(&統計.度数分布)
    )
}

/// 度数分布を「区分の下限=画素数」の並びにする。区分の上端を書かないのは、次の区分の下限がそれを表すためである。
fn 度数分布の行を作る(度数分布: &[u64; 6]) -> String {
    let 区分一覧: Vec<String> = 度数分布の区分の下限
        .iter()
        .zip(度数分布)
        .map(|(下限, 画素数)| format!("{下限}以上{画素数}画素"))
        .collect();
    区分一覧.join("、")
}

pub(super) fn 格納バイト数の行を作る(素材名: &str, 非圧縮: u64, ブロック圧縮: u64) -> Result<String, String> {
    if ブロック圧縮 == 0 {
        return Err(format!("{素材名}のブロック圧縮の実行時形式が0バイトである"));
    }
    let 倍率の百分率 = 非圧縮 * 100 / ブロック圧縮;
    Ok(format!(
        "{素材名}の実行時形式は非圧縮{非圧縮}バイト・ブロック圧縮{ブロック圧縮}バイト({}分の1)",
        百分率を小数の見た目にする(倍率の百分率)
    ))
}

fn 千分率を小数の見た目にする(値: u64) -> String {
    format!("{}.{:03}", 値 / 1000, 値 % 1000)
}

fn 百分率を小数の見た目にする(値: u64) -> String {
    format!("{}.{:02}", 値 / 100, 値 % 100)
}
