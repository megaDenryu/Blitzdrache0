//! ブロック圧縮の検収エラーを人が読む1文へ写すトレイト実装。枝ごとに、どの前提がどう破れたかを出す。
//! 実装を型の定義と分けるのは、外部トレイトの実装が型自身の持ち物とは別の軸であるためである。

use std::fmt;

use super::ブロック圧縮の検収エラー;

impl fmt::Display for ブロック圧縮の検収エラー {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::検収の器が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::判定が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::検証用ソースアセットを生成できなかった => write!(書き手, "検証用ソースアセットの生成に失敗した"),
            Self::世界を方針違いで焼けなかった {
                世界,
                方針の名前,
                出力ルート,
            } => write!(書き手, "{世界}を{方針の名前}で{出力ルート}へ焼けなかった"),
            Self::実行時形式の大きさを読めなかった { パス, 誤り } => {
                write!(書き手, "{}の大きさを読めない: {誤り}", パス.display())
            }
            Self::実行時形式を読めなかった { パス, 誤り } => write!(書き手, "{}を読めない: {誤り}", パス.display()),
            Self::区画を拡大する道具を起こせなかった { 誤り } => {
                write!(書き手, "ImageMagickを起動できなかった: {誤り}")
            }
            Self::区画を拡大する道具が失敗して終わった { 終了状態 } => {
                write!(書き手, "ImageMagickが{終了状態}で失敗した")
            }
            Self::拡大した絵の絶対パスを取れなかった { パス, 誤り } => {
                write!(書き手, "{}の絶対パスを取れなかった: {誤り}", パス.display())
            }
            Self::条件の絵を撮れなかった { 条件の呼び名, 破れ } => write!(書き手, "{条件の呼び名}: {破れ}"),
        }
    }
}
