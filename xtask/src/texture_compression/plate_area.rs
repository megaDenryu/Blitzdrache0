//! 対照の板2枚が読み戻し画像のどこを占めるかの正本。担当するのは、素材ごとの判定領域を1箇所で決めることである。
//!
//! 領域を画面の左半分と右半分にできるのは、2枚の板がワールドのx=0の辺を共有して隙間なく並び、
//! 既定カメラが原点を+Z軸上から正対して見ているためである。この構図では、板の境界が画面の横中央へちょうど写り、
//! 板の外周は画面の外へ出る。したがって左半分の全画素が滑らかなグラデーション、右半分の全画素が決定的な雑音になる。
//!
//! 注意: この対応は板の寸法と既定カメラの姿勢に依存する。どちらかを変えたら領域の取り方から作り直す。

use crate::pixel_region::画面領域;

/// 左半分。滑らかなグラデーションを持つ板が占める。
pub(super) fn グラデーションの板の領域(幅: usize, 高さ: usize) -> 画面領域 {
    画面領域 {
        x開始: 0,
        x終端: 幅 / 2,
        y開始: 0,
        y終端: 高さ,
    }
}

/// 右半分。決定的な雑音を持つ板が占める。幅が奇数のときに中央の1列を右へ入れるのは、
/// 左右のどちらへ寄せても判定が変わらない画素であり、切り捨ての向きを1つに決めれば足りるためである。
pub(super) fn 雑音の板の領域(幅: usize, 高さ: usize) -> 画面領域 {
    画面領域 {
        x開始: 幅 / 2,
        x終端: 幅,
        y開始: 0,
        y終端: 高さ,
    }
}
