//! 対照の板の検収。担当するのは、対照の世界を方針違いに焼き、同じ構図で描き、決定性と誤差の統計を判定し、
//! 報告の行を組み立てるところまでである。ヘルメットの目視材料は`helmet_run`が持つ。
//!
//! 決定性を焼き付けと描画の2段で見るのは、破れうる場所が2つあるためである。焼き付けは符号化器と縮小段の生成が
//! 同じ入力から同じバイト列を出すことの検査であり、描画はGPUの復号と描画経路が同じ入力から同じ絵を出すことの検査である。

use std::path::Path;

use super::world_bake::{実行時形式のバイト数を読む, 実行時形式のパス, 対照の板のシーン名};
use super::{difference, draw, judgment, plate_area, summary, world_bake};

pub(super) fn 対照の板を検収する(出力先: &Path) -> Result<Vec<String>, String> {
    let (ルート, 再現ルート) = world_bake::対照の板の世界を方針違いで焼く()?;
    焼き付けの決定性を確かめる(&ルート.ブロック圧縮, &再現ルート)?;

    let 非圧縮 = draw::描いてpngへ書き出す(&ルート.非圧縮, 対照の板のシーン名, &出力先.join("contrast_rgba8"), "対照の板(全てRGBA8)")?;
    let 圧縮 = draw::描いてpngへ書き出す(
        &ルート.ブロック圧縮,
        対照の板のシーン名,
        &出力先.join("contrast_bc1"),
        "対照の板(ベースカラーのブロック圧縮)",
    )?;
    let 再実行 = draw::描く(
        &ルート.ブロック圧縮,
        対照の板のシーン名,
        &出力先.join("contrast_bc1_repeat"),
        "対照の板(ベースカラーのブロック圧縮、2実行目)",
    )?;
    judgment::バイト一致を確かめる("ブロック圧縮の方針の2実行の読み戻し画像", &圧縮.画像.rgba8, &再実行.rgba8)?;

    let mut 行一覧 = 誤差の統計を判定する(&非圧縮.画像, &圧縮.画像)?;
    行一覧.push(summary::格納バイト数の行を作る(
        "対照の板",
        実行時形式のバイト数を読む(&ルート.非圧縮, 対照の板のシーン名)?,
        実行時形式のバイト数を読む(&ルート.ブロック圧縮, 対照の板のシーン名)?,
    )?);
    行一覧.push(format!("対照の板の絵は{}と{}", 非圧縮.png.display(), 圧縮.png.display()));
    Ok(行一覧)
}

/// 同じ方針で2度焼いた実行時形式が1バイトも違わないことを確かめる。
fn 焼き付けの決定性を確かめる(ブロック圧縮ルート: &Path, 再現ルート: &Path) -> Result<(), String> {
    let 一度目 = 実行時形式を読む(ブロック圧縮ルート)?;
    let 二度目 = 実行時形式を読む(再現ルート)?;
    judgment::バイト一致を確かめる("同じ方針で2度焼いた対照の板の実行時形式", &一度目, &二度目)
}

fn 実行時形式を読む(出力ルート: &Path) -> Result<Vec<u8>, String> {
    let パス = 実行時形式のパス(出力ルート, 対照の板のシーン名);
    std::fs::read(&パス).map_err(|誤り| format!("{}を読めない: {誤り}", パス.display()))
}

/// 素材ごとに領域を分けて統計を採り、素材ごとの判定値で判定する。1枚にまとめないのは、
/// 端点の丸めによる段差と線分へ載せられない色の誤差が別の現象であり、同じ上界で見ると片方が必ず薄まるためである。
fn 誤差の統計を判定する(
    非圧縮: &crate::vegetation_run::実行結果, 圧縮: &crate::vegetation_run::実行結果
) -> Result<Vec<String>, String> {
    let (幅, 高さ) = (非圧縮.幅, 非圧縮.高さ);
    let グラデーション = difference::領域内の成分差の統計を求める(非圧縮, 圧縮, &plate_area::グラデーションの板の領域(幅, 高さ))?;
    let 雑音 = difference::領域内の成分差の統計を求める(非圧縮, 圧縮, &plate_area::雑音の板の領域(幅, 高さ))?;
    judgment::グラデーションの板を判定する(&グラデーション)?;
    judgment::雑音の板を判定する(&雑音)?;
    Ok(vec![
        summary::統計の行を作る("滑らかなグラデーション", &グラデーション),
        summary::統計の行を作る("決定的な雑音", &雑音),
    ])
}
