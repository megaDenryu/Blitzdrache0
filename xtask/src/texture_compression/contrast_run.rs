//! 対照の板の検収。担当するのは、対照の世界を方針違いに焼き、同じ構図で描き、決定性と誤差の統計を判定し、
//! 報告の行を組み立てるところまでである。ヘルメットの目視材料は`helmet_run`が持つ。
//!
//! 決定性を焼き付けと描画の2段で見るのは、破れうる場所が2つあるためである。焼き付けは符号化器と縮小段の生成が
//! 同じ入力から同じバイト列を出すことの検査であり、描画はGPUの復号と描画経路が同じ入力から同じ絵を出すことの検査である。

use std::path::{Path, PathBuf};

use crate::acceptance::読み戻し画像;

use super::baked_scene::対照の板のシーン名;
use super::error::ブロック圧縮の検収エラー;
use super::{baked_scene, difference, draw, judgment, plate_area, summary, world_bake};

const 非圧縮の条件の呼び名: &str = "対照の板(全てRGBA8)";
const 圧縮の条件の呼び名: &str = "対照の板(ベースカラーのブロック圧縮)";
const 圧縮の2実行目の条件の呼び名: &str = "対照の板(ベースカラーのブロック圧縮、2実行目)";

pub(super) fn 対照の板を検収する(出力先: &Path) -> Result<Vec<String>, ブロック圧縮の検収エラー> {
    let (ルート, 再現ルート) = world_bake::対照の板の世界を方針違いで焼く()?;
    焼き付けの決定性を確かめる(&ルート.ブロック圧縮, &再現ルート)?;

    let 出力ディレクトリ = PathBuf::from(出力先);
    let 非圧縮の実行環境 = draw::実行環境を作る(&ルート.非圧縮, 出力ディレクトリ.clone())?;
    let 圧縮の実行環境 = draw::実行環境を作る(&ルート.ブロック圧縮, 出力ディレクトリ)?;

    let 非圧縮 =
        draw::条件1つを描いて読み戻しをpngへ書き出す(&非圧縮の実行環境, 対照の板のシーン名, "contrast_rgba8", 非圧縮の条件の呼び名)?;
    let 圧縮 =
        draw::条件1つを描いて読み戻しをpngへ書き出す(&圧縮の実行環境, 対照の板のシーン名, "contrast_bc1", 圧縮の条件の呼び名)?;
    let 再実行 = draw::条件1つを描いて読み戻す(&圧縮の実行環境, 対照の板のシーン名, "contrast_bc1_repeat", 圧縮の2実行目の条件の呼び名)?;
    judgment::バイト一致を確かめる("ブロック圧縮の方針の2実行の読み戻し画像", 圧縮.画像.バイト列(), 再実行.バイト列())?;

    let mut 行一覧 = 誤差の統計を判定する(&非圧縮.画像, &圧縮.画像)?;
    行一覧.push(summary::格納バイト数の行を作る(
        "対照の板",
        baked_scene::対照の板の格納バイト数を読む(&ルート.非圧縮)?,
        baked_scene::対照の板の格納バイト数を読む(&ルート.ブロック圧縮)?,
    )?);
    行一覧.push(format!("対照の板の絵は{}と{}", 非圧縮.png.display(), 圧縮.png.display()));
    Ok(行一覧)
}

/// 同じ方針で2度焼いた実行時形式が1バイトも違わないことを確かめる。
fn 焼き付けの決定性を確かめる(
    ブロック圧縮ルート: &Path, 再現ルート: &Path
) -> Result<(), ブロック圧縮の検収エラー> {
    let 一度目 = baked_scene::対照の板の実行時形式を読む(ブロック圧縮ルート)?;
    let 二度目 = baked_scene::対照の板の実行時形式を読む(再現ルート)?;
    Ok(judgment::バイト一致を確かめる(
        "同じ方針で2度焼いた対照の板の実行時形式",
        &一度目,
        &二度目,
    )?)
}

/// 素材ごとに領域を分けて統計を採り、素材ごとの判定値で判定する。1枚にまとめないのは、
/// 端点の丸めによる段差と線分へ載せられない色の誤差が別の現象であり、同じ上界で見ると片方が必ず薄まるためである。
fn 誤差の統計を判定する(
    非圧縮: &読み戻し画像, 圧縮: &読み戻し画像
) -> Result<Vec<String>, ブロック圧縮の検収エラー> {
    let (幅, 高さ) = (非圧縮.幅().画素数(), 非圧縮.高さ().画素数());
    let グラデーション = difference::領域内の成分差の統計を求める(非圧縮, 圧縮, &plate_area::グラデーションの板の領域(幅, 高さ))?;
    let 雑音 = difference::領域内の成分差の統計を求める(非圧縮, 圧縮, &plate_area::雑音の板の領域(幅, 高さ))?;
    judgment::グラデーションの板を判定する(&グラデーション)?;
    judgment::雑音の板を判定する(&雑音)?;
    Ok(vec![
        summary::統計の行を作る("滑らかなグラデーション", &グラデーション),
        summary::統計の行を作る("決定的な雑音", &雑音),
    ])
}
