//! ブロック圧縮の検収が返す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。
//! 様式は`acceptance/error.rs`と`acceptance/error/readback_break.rs`に倣う。
//!
//! 検収の器の破れと判定の破れを枝で内包するのは、この入口が絵を撮る工程と判定の工程と実行時形式の操作を
//! 一続きに通すためである。3つを別の型で返すと、通す側が段ごとに変換を書くことになる。
//!
//! 判定でも報告の読み取りでもない破れをここが持つのは、実行時形式の焼き付けと格納バイト数の読み取りと
//! 目視用の拡大が、どれもこの入口だけが行う外部への働きかけだからである。人が読む1文へ写すのは`display`が持つ。

mod display;

use std::path::PathBuf;

use crate::acceptance::{判定の破れ, 検収エラー};
use crate::asset_generator::世界名;

#[derive(Debug)]
pub(super) enum ブロック圧縮の検収エラー {
    /// 絵を撮る器の破れ。どの実行で落ちたかは器の側が名指す。
    検収の器が破れた(検収エラー),
    判定が破れた(判定の破れ),
    検証用ソースアセットを生成できなかった,
    世界を方針違いで焼けなかった {
        世界: 世界名,
        方針の名前: &'static str,
        出力ルート: &'static str,
    },
    実行時形式の大きさを読めなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    実行時形式を読めなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    /// 撮った絵の一区画を切り取って拡大する外部の道具を起こせなかった。
    区画を拡大する道具を起こせなかった {
        誤り: std::io::Error,
    },
    区画を拡大する道具が失敗して終わった {
        終了状態: String,
    },
    拡大した絵の絶対パスを取れなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    /// その条件の絵を撮る段で器が破れた。どの条件を撮ろうとしていたかを添える。
    条件の絵を撮れなかった {
        条件の呼び名: &'static str,
        破れ: 検収エラー,
    },
}

impl std::error::Error for ブロック圧縮の検収エラー {}

impl From<検収エラー> for ブロック圧縮の検収エラー {
    fn from(破れ: 検収エラー) -> Self {
        Self::検収の器が破れた(破れ)
    }
}

impl From<判定の破れ> for ブロック圧縮の検収エラー {
    fn from(破れ: 判定の破れ) -> Self {
        Self::判定が破れた(破れ)
    }
}
