//! 誤差の統計に対する判定値と判定。担当するのは、どの素材のどの統計量にどの上界と下界を課すかである。
//! 統計の求め方は`difference`が、素材が画面のどこを占めるかは`plate_area`が持つ。
//!
//! 判定値はすべて、対照の素材と既定の構図という固定入力での実測から余白を持って制定した値である。
//! 品質の契約でもBC1という形式の一般的な性質でもない。入力か構図を変えたら測り直して制定し直す。
//! 参照: `_doc/設計/テクスチャのブロック圧縮と縮小段生成.md`「検収戦略(判断g)」

use super::difference::画素の成分差の統計;
use crate::acceptance::{判定の名前, 判定の破れ};

/// 滑らかなグラデーションの板の成分差の上界。制定時(2026-08-09)の実測は最大5符号値・平均1.079符号値であり、
/// 起動をまたいだ実測は下3桁が動きうる(契約は同一起動内の決定性だけが持つ)。
/// 端点をRGB565へ丸めたときの段差がこの水準に収まることを見る。倍以上の余白を取るのは、
/// 補間の実装差がBC1からBC3の復号に許されており、機材が変われば下位の数符号値が動きうるためである。
const グラデーションの成分差の最大の上界: u64 = 12;
const グラデーションの成分差の平均の千分率の上界: u64 = 3000;

/// 決定的な雑音の板の成分差の上界。最大に上界を制定しないのは、1本の線分へ載せられない色の誤差が
/// 入力の色の散らばりだけで決まり、実測200符号値が符号値の全域に迫るためである。
/// 全域に迫る上界は壊れた符号化器も通してしまい判定として働かないため、分布の代表値である平均で見る。
/// 制定時(2026-08-09)の実測は平均31.971符号値である。
const 雑音の成分差の平均の千分率の上界: u64 = 60000;

/// ブロック圧縮の経路が実際に効いていることの反証に使う下界。方針の取り違えで同じ絵を2枚並べ、
/// 「差が小さいから合格」と読む事故を防ぐために置く。実測の4分の1と、量子化が起きれば必ず超える1符号値である。
const 雑音の成分差の平均の千分率の下界: u64 = 8000;
const グラデーションの成分差の最大の下界: u64 = 1;

const グラデーションの板の成分差の最大: 判定の名前 = 判定の名前::定数から生成する("グラデーションの板の成分差の最大");
const グラデーションの板の成分差の平均の千分率: 判定の名前 = 判定の名前::定数から生成する("グラデーションの板の成分差の平均の千分率");
const 雑音の板の成分差の平均の千分率: 判定の名前 = 判定の名前::定数から生成する("雑音の板の成分差の平均の千分率");

/// 下界を課す判定を上界と別の名前で持つのは、下界の破れだけが「ブロック圧縮の経路が効いていない」という
/// 別の見立てを指すためである。その見立てを名前の括弧書きへ畳んで、破れの文面から読めるようにする。
const 経路が効いている証拠のグラデーションの板の成分差の最大: 判定の名前 =
    判定の名前::定数から生成する("グラデーションの板の成分差の最大(下界に届かないならブロック圧縮の経路が効いていない疑いがある)");
const 経路が効いている証拠の雑音の板の成分差の平均の千分率: 判定の名前 =
    判定の名前::定数から生成する("雑音の板の成分差の平均の千分率(下界に届かないならブロック圧縮の経路が効いていない疑いがある)");

pub(super) fn グラデーションの板を判定する(統計: &画素の成分差の統計) -> Result<(), 判定の破れ> {
    グラデーションの板の成分差の最大.上限を課す(統計.最大, グラデーションの成分差の最大の上界)?;
    グラデーションの板の成分差の平均の千分率.上限を課す(統計.平均の千分率, グラデーションの成分差の平均の千分率の上界)?;
    経路が効いている証拠のグラデーションの板の成分差の最大.下限を課す(統計.最大, グラデーションの成分差の最大の下界)
}

pub(super) fn 雑音の板を判定する(統計: &画素の成分差の統計) -> Result<(), 判定の破れ> {
    雑音の板の成分差の平均の千分率.上限を課す(統計.平均の千分率, 雑音の成分差の平均の千分率の上界)?;
    経路が効いている証拠の雑音の板の成分差の平均の千分率.下限を課す(統計.平均の千分率, 雑音の成分差の平均の千分率の下界)
}

/// 2つのバイト列が一致するか。決定性の検査は焼いた実行時形式と読み戻し画像の両方でこれを使う。
/// 食い違ったバイトの数を零件として課すのは、一致しないことだけでなくどの程度の破れかを文面が言うためである。
pub(super) fn バイト一致を確かめる(名前: &str, 左: &[u8], 右: &[u8]) -> Result<(), 判定の破れ> {
    if 左 == 右 {
        return Ok(());
    }
    食い違いの判定名(名前, 左, 右).零件であることを課す(食い違ったバイト数を数える(左, 右))
}

/// 長さの違いも食い違いとして数える。短い側に無いバイトは、位置ごとに突き合わせれば必ず食い違うためである。
fn 食い違ったバイト数を数える(左: &[u8], 右: &[u8]) -> usize {
    左.iter().zip(右).filter(|(左値, 右値)| 左値 != 右値).count() + 左.len().abs_diff(右.len())
}

fn 食い違いの判定名(名前: &str, 左: &[u8], 右: &[u8]) -> 判定の名前 {
    let 違う位置 = 左.iter().zip(右).position(|(左値, 右値)| 左値 != 右値);
    判定の名前::組み立てた綴りから生成する(format!(
        "{名前}で食い違ったバイト(長さ{}と{}、最初に違うバイトの位置{違う位置:?})",
        左.len(),
        右.len()
    ))
}
