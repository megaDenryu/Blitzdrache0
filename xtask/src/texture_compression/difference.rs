//! 同じ構図の2枚の読み戻し画像の、指定領域における成分差の統計。受け取るのは2枚の画像と領域、
//! 返すのは最大・平均・差のある画素数・度数分布である。どの領域をどの素材と見なすかは呼び出し元の判定が決める。
//!
//! 平均を千分率の整数で持つのは、浮動小数の丸めが実行のたびに違う下位桁を作ることを避けるためである。
//! 判定値も同じ単位で書けるため、報告の値と判定値を突き合わせるときに単位の変換が要らない。

use crate::acceptance::{画素の番号, 読み戻し画像};
use crate::pixel_region::画面領域;

/// 度数分布の各区分の下限。画素ごとの赤・緑・青の差のうち最も大きいものを、この境界で6つの区分へ入れる。
pub const 度数分布の区分の下限: [u64; 6] = [0, 1, 2, 4, 8, 16];

pub struct 画素の成分差の統計 {
    /// 領域内の全成分の差のうち最も大きいもの。単位は符号値である。
    pub 最大: u64,
    /// 領域内の全成分の差の平均。単位は符号値の千分の1である。
    pub 平均の千分率: u64,
    /// 3成分のいずれかが1でも違う画素の数。
    pub 差のある画素数: u64,
    pub 画素数: u64,
    pub 度数分布: [u64; 6],
}

pub fn 領域内の成分差の統計を求める(
    左: &読み戻し画像,
    右: &読み戻し画像,
    領域: &画面領域,
) -> Result<画素の成分差の統計, String> {
    if !左.寸法が同じか(右) {
        return Err(format!("比べる2枚の寸法が違う: {}と{}", 左.寸法の綴り(), 右.寸法の綴り()));
    }
    if 領域.x終端 > 左.幅().画素数() || 領域.y終端 > 左.高さ().画素数() {
        return Err(format!("判定領域が読み戻し画像({})の外にある", 左.寸法の綴り()));
    }
    let mut 統計 = 画素の成分差の統計 {
        最大: 0,
        平均の千分率: 0,
        差のある画素数: 0,
        画素数: 領域.画素数(),
        度数分布: [0; 6],
    };
    let mut 合計 = 0u64;
    for y in 領域.y開始..領域.y終端 {
        for x in 領域.x開始..領域.x終端 {
            合計 += 画素1つを統計へ加える(&mut 統計, 左, 右, y * 左.幅().画素数() + x);
        }
    }
    if 統計.画素数 == 0 {
        return Err("判定領域が空である".to_string());
    }
    統計.平均の千分率 = 合計 * 1000 / (統計.画素数 * 3);
    Ok(統計)
}

/// 1画素の3成分の差を統計へ反映し、その画素の3成分の差の合計を返す。
fn 画素1つを統計へ加える(
    統計: &mut 画素の成分差の統計, 左: &読み戻し画像, 右: &読み戻し画像, 画素番号: usize
) -> u64 {
    let (左の色, 右の色) = (
        左.番号の画素(画素の番号::生成する(画素番号)),
        右.番号の画素(画素の番号::生成する(画素番号)),
    );
    let mut 画素内の最大 = 0u64;
    let mut 画素内の合計 = 0u64;
    for (左の成分, 右の成分) in 左の色.iter().zip(右の色.iter()) {
        let 差 = u64::from(左の成分.abs_diff(*右の成分));
        画素内の合計 += 差;
        画素内の最大 = 画素内の最大.max(差);
    }
    統計.最大 = 統計.最大.max(画素内の最大);
    if 画素内の最大 > 0 {
        統計.差のある画素数 += 1;
    }
    統計.度数分布[度数分布の区分の添字を求める(画素内の最大)] += 1;
    画素内の合計
}

/// その差が入る度数分布の区分。下限の一覧を後ろから見て最初に届いた区分を返す。
fn 度数分布の区分の添字を求める(差: u64) -> usize {
    度数分布の区分の下限.iter().rposition(|下限| 差 >= *下限).unwrap_or(0)
}
