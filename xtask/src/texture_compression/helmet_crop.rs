//! DamagedHelmetの絵から一区画を切り取って拡大する工程。受け取るのは元の絵のパスと出力先、
//! 返すのは書き出したPNGの絶対パスである。
//!
//! 拡大した対を添えるのは、ヘルメットが1280x720の画面の一部しか占めず、原寸のままではベースカラーの
//! 段差が目で追えないためである。拡大に最近傍を使うのは画素そのものを見せるためであり、滑らかな補間で
//! 拡大すると量子化の段差が補間に埋もれる。道具をImageMagickに揃えるのは`raw_png`と同じ理由である。
//! 参照: `xtask/src/temporal_visual/crop.rs`(同じ様式の先例)

use std::path::{Path, PathBuf};
use std::process::Command;

use super::error::ブロック圧縮の検収エラー;
use crate::acceptance::{判定の名前, 判定の破れ};

/// 切り取る区画。既定カメラで撮ったヘルメットの、面の広い金属板と暗い外殻が同時に入る位置である。
/// 明るい面はベースカラーの段差が、暗い外殻は端点の丸めによる色の偏りが出やすい。
/// 単位を画素の位置と同じ`usize`で持つのは、撮った絵の寸法と直に比べるためである。
const 起点横: usize = 490;
const 起点縦: usize = 270;
const 区画の横: usize = 320;
const 区画の縦: usize = 180;
/// 拡大率。320x180を1280x720へ引き伸ばし、元の絵と同じ大きさで並べられる。
const 拡大率: usize = 400;

const 切り取る区画の右端: 判定の名前 = 判定の名前::定数から生成する("切り取る区画の右端(撮った絵の幅を超えるとはみ出す)");
const 切り取る区画の下端: 判定の名前 = 判定の名前::定数から生成する("切り取る区画の下端(撮った絵の高さを超えるとはみ出す)");

/// 切り取りが絵の中に収まることを、撮った絵の寸法から確かめる。
pub(super) fn 区画が絵に収まるか確かめる(幅: usize, 高さ: usize) -> Result<(), 判定の破れ> {
    切り取る区画の右端.上限を課す(起点横 + 区画の横, 幅)?;
    切り取る区画の下端.上限を課す(起点縦 + 区画の縦, 高さ)
}

pub(super) fn ヘルメットの区画を切り取って拡大する(
    元の絵: &Path,
    出力先: &Path,
) -> Result<PathBuf, ブロック圧縮の検収エラー> {
    let 区画 = format!("{区画の横}x{区画の縦}+{起点横}+{起点縦}");
    let 状態 = Command::new("magick")
        .arg(元の絵)
        .args(["-crop", &区画, "+repage"])
        .args(["-filter", "point", "-resize", &format!("{拡大率}%")])
        .arg(出力先)
        .status()
        .map_err(|誤り| ブロック圧縮の検収エラー::区画を拡大する道具を起こせなかった { 誤り })?;
    if !状態.success() {
        return Err(ブロック圧縮の検収エラー::区画を拡大する道具が失敗して終わった {
            終了状態: 状態.to_string()
        });
    }
    let 絶対パス = std::fs::canonicalize(出力先);
    絶対パス.map_err(|誤り| ブロック圧縮の検収エラー::拡大した絵の絶対パスを取れなかった {
        パス: 出力先.to_path_buf(),
        誤り,
    })
}
