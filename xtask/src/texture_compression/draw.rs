//! ブロック圧縮の検収1条件ぶんの起動の指定と、その実行の絵の取り込み。受け取るのは実行環境と実行名、
//! 返すのは読み戻し画像とPNGのパスである。起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! 起動指定のうち条件で振るものは1つも無い。同じシーンを同じ構図で撮り、絵の差の由来を
//! テクスチャ格納方針だけに帰属させることがこの入口の目的であり、それ以外が1つでも違うと差が読めなくなる。
//! 方針の違いは実行環境が保持するアセットルートの違いとして現れる。
//!
//! フレーム数を30に留めるのは、この世界が空も間接照明の焼き上げも持たず、1フレーム目から定常であるためである。

use std::path::{Path, PathBuf};

use super::error::ブロック圧縮の検収エラー;
use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収の1回の実行, 検収の実行名, 検収エラー,
    検収シーン名, 読み戻し画像,
};

const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(30);

pub(super) struct 撮った絵 {
    pub(super) 画像: 読み戻し画像,
    pub(super) png: PathBuf,
}

/// 1つの出力ルートを読む実行環境。方針ごとにルートが分かれるため、方針ごとに1つ作る。
pub(super) fn 実行環境を作る(
    アセットルート: &Path, 出力ディレクトリ: PathBuf
) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::パスから生成する(アセットルート.to_path_buf()),
        出力ディレクトリ,
    )
}

/// 1条件を描き、読み戻しを目視用のPNGへ書き出す。条件の呼び名は破れの文面がどの条件を撮ろうとしていたかを言うために受ける。
pub(super) fn 条件1つを描いて読み戻しをpngへ書き出す(
    実行環境: &描画検収の実行環境,
    シーン名: 検収シーン名,
    実行名の綴り: &str,
    条件の呼び名: &'static str,
) -> Result<撮った絵, ブロック圧縮の検収エラー> {
    let 実行 = 描く(実行環境, シーン名, 実行名の綴り, 条件の呼び名)?;
    let png = 実行
        .書き出し先()
        .目視用の絵へ変換する()
        .map_err(|破れ| 条件の絵の破れにする(条件の呼び名, 破れ))?;
    Ok(撮った絵 {
        画像: 実行.画像を取り出す(),
        png,
    })
}

pub(super) fn 条件1つを描いて読み戻す(
    実行環境: &描画検収の実行環境,
    シーン名: 検収シーン名,
    実行名の綴り: &str,
    条件の呼び名: &'static str,
) -> Result<読み戻し画像, ブロック圧縮の検収エラー> {
    Ok(描く(実行環境, シーン名, 実行名の綴り, 条件の呼び名)?.画像を取り出す())
}

fn 描く(
    実行環境: &描画検収の実行環境,
    シーン名: 検収シーン名,
    実行名の綴り: &str,
    条件の呼び名: &'static str,
) -> Result<検収の1回の実行, ブロック圧縮の検収エラー> {
    let 実行名 = 検収の実行名::生成する(実行名の綴り).map_err(|破れ| 条件の絵の破れにする(条件の呼び名, 破れ))?;
    実行環境
        .描いて読み戻す(実行名, &アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数))
        .map_err(|破れ| 条件の絵の破れにする(条件の呼び名, 破れ))
}

fn 条件の絵の破れにする(条件の呼び名: &'static str, 破れ: 検収エラー) -> ブロック圧縮の検収エラー {
    ブロック圧縮の検収エラー::条件の絵を撮れなかった { 条件の呼び名, 破れ }
}
