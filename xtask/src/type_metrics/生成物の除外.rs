//! Graphiteの生成物を除いたファイルごとの観測と、除いた生成物の並び。受け取るのは走査した原文の一覧、返すのは観測の並びと除いた生成物のパスの並びである。
//!
//! 計測は手で書いた型への責務の集中を見るものであり、Graphiteの生成物が利用者の型へ足すimplは手で編集できず、その目的に当たらない。
//! しかも生成物は `include!` で取り込まれ物理と論理のモジュールが一致しないため、生成物の `super::型` を計測が物理のパスから解けない。
//! 単独の `cargo xtask type-metrics` と、conform の型ごとの分量の台帳の検査と親の型を丸ごと受け取る自由関数の検査が、同じこの値から観測を得る。
//! 入口ごとに除き方を書くと、片方だけが生成物を数える食い違いが起きるためである。除いた生成物は並びとして返し、呼び出し側が件数と名前を報告する。
//! 生成物の見分けは conform の `Graphiteの生成物の一覧`(見出しと生成元の宣言の結び付き)に任せ、ここでは判定しない。

use std::path::PathBuf;

use super::error::型計測の破れ;
use super::file_observation::ファイルの観測;
use super::走査対象の原文を集める;
use crate::conform::graphiteのコード::Graphiteの生成物の一覧;
use crate::conform::走査した原文の一覧::走査した原文の一覧;

/// Graphiteの生成物を除いたファイルごとの観測。除いた生成物のパスを一緒に持つ。
pub struct 生成物を除いた観測 {
    pub 観測一覧: Vec<ファイルの観測>,
    pub 除いた生成物一覧: Vec<PathBuf>,
}

impl 生成物を除いた観測 {
    /// 走査対象のRustファイルを読み、生成物を除いて観測へ写す。
    pub fn 走査対象から集める() -> Result<Self, 型計測の破れ> {
        Ok(Self::原文一覧から組む(&走査した原文の一覧::生成する(走査対象の原文を集める()?)))
    }

    /// 読んだ原文の一覧から、見出しで認めた生成物を除いて観測へ写す。
    pub fn 原文一覧から組む(原文一覧: &走査した原文の一覧) -> Self {
        let 生成物 = Graphiteの生成物の一覧::原文一覧から見分ける(原文一覧);
        let 観測一覧 = 原文一覧
            .並び()
            .filter(|(パス, _)| !生成物.生成物か(パス))
            .map(|(パス, 内容)| ファイルの観測::ファイルの内容から生成する(パス.to_path_buf(), 内容))
            .collect();
        Self {
            観測一覧,
            除いた生成物一覧: 生成物.生成物一覧().to_vec(),
        }
    }
}
