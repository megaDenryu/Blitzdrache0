//! 走査で見つけた型定義の索引と、implブロックを定義へ引き当てる判断。引き当てた結果の型は`impl_attribution`が持つ。
//!
//! 型を名前と定義ファイルの組で識別すると、implブロックだけが載っている行から所在が決まらない。
//! 同じ名前の型が別の場所に複数あるとき、そのimplがどちらの型のものかを決める必要がある。
//!
//! 判断は「証明できない帰属は推測しない」で行う。同名の定義が1件しかないならその定義であり、implと定義が
//! 同じファイルにあるならそのファイルの定義である(同じモジュールに在る名前を`use`で覆うことはできないため)。
//! それ以外は、implブロックが綴った経路か、そのファイルの`use`宣言が持ち込んだ経路を解決し、解決の先が
//! 候補のちょうど1件と重なったときだけ引き当てる。決まらなければ黙ってどちらかへ寄せず、引き当てられなかった
//! こととして呼び出し側へ返す。ファイルやディレクトリの近さは根拠に使わない。inherent implに要るのは定義と
//! 同じクレートにあることだけであり、離れたモジュールのファイルに置いてよいためである。

use std::collections::BTreeMap;

use super::attribution_input::引き当ての材料;
use super::file_observation::ファイルの観測;
use super::impl_attribution::{定義の候補が複数ある実装ブロック, 実装ブロックの引き当て};
use super::observation::観測;
use super::type_location::型の所在;

pub struct 定義の索引 {
    型名ごとの定義の所在: BTreeMap<String, Vec<型の所在>>,
}

impl 定義の索引 {
    pub fn ファイル別の観測から生成する(ファイル別観測: &[ファイルの観測]) -> Self {
        let mut 型名ごとの定義の所在: BTreeMap<String, Vec<型の所在>> = BTreeMap::new();
        for ファイル in ファイル別観測 {
            for 観測 in &ファイル.観測一覧 {
                let 観測::型定義 { 型名, .. } = 観測 else { continue };
                let 所在 = 型の所在::走査したファイルから生成する(&ファイル.パス, 型名);
                let 一覧 = 型名ごとの定義の所在.entry(型名.clone()).or_default();
                if !一覧.contains(&所在) {
                    一覧.push(所在);
                }
            }
        }
        Self {
            型名ごとの定義の所在
        }
    }

    pub fn 実装ブロックの所在を引き当てる(&self, 材料: &引き当ての材料) -> 実装ブロックの引き当て {
        let 候補一覧 = self.型名ごとの定義の所在.get(材料.型名()).map_or(&[][..], Vec::as_slice);
        match 候補一覧 {
            [] => 実装ブロックの引き当て::所在が決まった(材料.実装ブロックのファイルを所在にする()),
            [唯一の定義] => 実装ブロックの引き当て::所在が決まった(唯一の定義.clone()),
            _ => 複数の候補から絞る(材料, 候補一覧),
        }
    }
}

fn 複数の候補から絞る(材料: &引き当ての材料, 候補一覧: &[型の所在]) -> 実装ブロックの引き当て {
    if let Some(同じファイルの定義) = 候補一覧.iter().find(|所在| 材料.実装ブロックのファイルに定義があるか(所在))
    {
        return 実装ブロックの引き当て::所在が決まった(同じファイルの定義.clone());
    }
    let 経路が指すファイル一覧 = 材料.経路が指す定義ファイル一覧();
    let 絞り込み: Vec<&型の所在> = 候補一覧
        .iter()
        .filter(|所在| 経路が指すファイル一覧.iter().any(|綴り| 綴り.as_str() == 所在.定義ファイルの綴り()))
        .collect();
    match 絞り込み.as_slice() {
        [唯一の定義] => 実装ブロックの引き当て::所在が決まった((*唯一の定義).clone()),
        _ => 実装ブロックの引き当て::定義の候補を1つに絞れない(定義の候補が複数ある実装ブロック::生成する(
            材料.実装ブロックのファイルのパス(),
            材料.型名().to_string(),
            候補一覧.to_vec(),
        )),
    }
}
