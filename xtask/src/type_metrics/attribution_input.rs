//! implブロック1件を定義へ引き当てるための材料。どのファイルに書かれたか、実装対象として何を綴ったか、
//! そのファイルが`use`で何を持ち込んだかの3つである。
//!
//! 3つを1つの値にするのは、引き当ての判断がこの3つを常に揃って使うためである。呼び出し側に並べて運ばせると、
//! 取り込みの索引だけ別のファイルのものを渡した形が型の上で通ってしまう。

use std::path::{Path, PathBuf};

use super::import_index::取り込みの索引;
use super::type_location::{ファイルの綴りへ揃える, 型の所在};
use super::type_path::自己型の経路;

pub struct 引き当ての材料<'a> {
    実装ブロックのファイル: &'a Path,
    自己型の経路: &'a 自己型の経路,
    取り込みの索引: &'a 取り込みの索引,
}

impl<'a> 引き当ての材料<'a> {
    pub fn 生成する(
        実装ブロックのファイル: &'a Path, 自己型の経路: &'a 自己型の経路, 取り込みの索引: &'a 取り込みの索引
    ) -> Self {
        Self {
            実装ブロックのファイル,
            自己型の経路,
            取り込みの索引,
        }
    }

    pub fn 型名(&self) -> &str {
        self.自己型の経路.型名()
    }

    pub fn 実装ブロックのファイルのパス(&self) -> PathBuf {
        self.実装ブロックのファイル.to_path_buf()
    }

    /// 定義が走査に1つも現れない型のimplブロックの所在。読み手が開ける唯一のファイルがこのファイルだからである。
    pub fn 実装ブロックのファイルを所在にする(&self) -> 型の所在 {
        型の所在::走査したファイルから生成する(self.実装ブロックのファイル, self.型名())
    }

    pub fn 実装ブロックのファイルに定義があるか(&self, 所在: &型の所在) -> bool {
        所在.定義ファイルの綴り() == ファイルの綴りへ揃える(self.実装ブロックのファイル)
    }

    /// 自己型が段を1つも書かず、`use`宣言も解ける経路を1件も持ち込んでいないか。この形のときだけ、
    /// 同じファイルに在る定義を引き当ての根拠にしてよい。段を書いた自己型は、その経路の指す先だけが
    /// 実装対象であり、同じファイルに同じ名前の定義があってもその定義ではないためである。
    pub fn 自己型も取り込みも場所を決めていないか(&self) -> bool {
        !self.自己型の経路.経路を明示しているか() && self.経路が指す定義ファイル一覧().is_empty()
    }

    /// 実装対象の定義があるはずのファイルの綴り。経路が段を書いているならその経路だけを解き、書いていないときだけ
    /// `use`宣言が持ち込んだ経路を解く。段が書かれているのに解けない経路(外部のクレートから始まる形)は空になる。
    pub fn 経路が指す定義ファイル一覧(&self) -> Vec<String> {
        if self.自己型の経路.経路を明示しているか() {
            return self.自己型の経路.定義ファイルの候補一覧(self.実装ブロックのファイル);
        }
        self.取り込みの索引
            .型名から経路一覧を引く(self.型名())
            .iter()
            .flat_map(|経路| 経路.定義ファイルの候補一覧(self.実装ブロックのファイル))
            .collect()
    }
}
