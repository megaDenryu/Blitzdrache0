//! 1つのファイルを走査して得た結果。パスと観測の並びと、そのファイルが`use`で持ち込んだ名前の索引の3つである。
//!
//! 3つを1つの値にするのは、implブロックの実装対象を引き当てるとき常に揃って要るためである。呼び出し側に
//! 並べて運ばせると、索引だけ渡し忘れた形が型の上で通ってしまう。

use std::path::PathBuf;

use super::import_index::取り込みの索引;
use super::observation::観測;

pub struct ファイルの観測 {
    pub パス: PathBuf,
    pub 観測一覧: Vec<観測>,
    pub 取り込みの索引: 取り込みの索引,
}

impl ファイルの観測 {
    pub fn ファイルの内容から生成する(パス: PathBuf, 内容: &str) -> Self {
        Self {
            パス,
            観測一覧: super::scan::走査する(内容),
            取り込みの索引: 取り込みの索引::ファイルの内容から生成する(内容),
        }
    }
}
