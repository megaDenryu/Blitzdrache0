//! 走査の観測を所在ごとの計測へ畳み込んでいく途中の表。
//!
//! 観測は「型定義1件」と「implブロック1件」がファイルの順に流れてくるだけであり、1つの型の計測は
//! 複数のファイルの観測が合わさって初めて出来上がる。その途中の可変の状態をこの型が所有し、
//! 取り込みをメソッドで行う。畳み終えたら結果の型へ移し、この型は消える。

use std::collections::BTreeMap;
use std::path::Path;

use super::declaration_amount::宣言の分量;
use super::impl_attribution::{定義の候補が複数ある実装ブロック, 実装ブロックの引き当て};
use super::metrics::{型計測, 走査範囲の型計測};
use super::type_location::型の所在;

pub struct 所在ごとの計測表 {
    所在ごとの計測: BTreeMap<型の所在, 型計測>,
    定義の候補を1つに絞れなかった実装ブロック一覧: Vec<定義の候補が複数ある実装ブロック>,
}

impl 所在ごとの計測表 {
    pub fn 空で始める() -> Self {
        Self {
            所在ごとの計測: BTreeMap::new(),
            定義の候補を1つに絞れなかった実装ブロック一覧: Vec::new(),
        }
    }

    /// 同じ所在に2つの定義行が現れるのは、同じファイルの中で`#[cfg]`により切り替わる型だけである。
    /// どちらの構成で数えるかを走査は決められないため、どちらかを残さず両方を一覧へ加える。
    pub fn 型定義を取り込む(&mut self, 所在: 型の所在, 分量: 宣言の分量) {
        self.計測を引く(所在).宣言.宣言を取り込む(分量);
    }

    pub fn 実装ブロックを取り込む(
        &mut self, 引き当て: 実装ブロックの引き当て, 実装ブロックのファイル: &Path, メソッド数: usize
    ) {
        match 引き当て {
            実装ブロックの引き当て::所在が決まった(所在) => {
                let 計測 = self.計測を引く(所在);
                計測.実装ファイル一覧.insert(実装ブロックのファイル.to_path_buf());
                計測.メソッド総数 += メソッド数;
            }
            実装ブロックの引き当て::定義の候補を1つに絞れない(実装ブロック) => {
                self.定義の候補を1つに絞れなかった実装ブロック一覧.push(実装ブロック);
            }
        }
    }

    /// 分量の大きい順に並べて結果の型へ移す。同じ分量の型は所在の綴りの順で並べ、走査の順に依らせない。
    pub fn 分量の降順へ並べて閉じる(self) -> 走査範囲の型計測 {
        let mut 型ごとの計測一覧: Vec<型計測> = self.所在ごとの計測.into_values().collect();
        型ごとの計測一覧.sort_by(|左, 右| 右.比較鍵().cmp(&左.比較鍵()).then_with(|| 左.所在.cmp(&右.所在)));
        走査範囲の型計測 {
            型ごとの計測一覧,
            定義の候補を1つに絞れなかった実装ブロック一覧: self.定義の候補を1つに絞れなかった実装ブロック一覧,
        }
    }

    fn 計測を引く(&mut self, 所在: 型の所在) -> &mut 型計測 {
        self.所在ごとの計測.entry(所在.clone()).or_insert_with(|| 型計測::所在だけで始める(所在))
    }
}
