//! implブロック1件を定義へ引き当てた結果。引き当てられた所在か、候補を1つに絞れなかった記録のどちらかである。
//!
//! 絞れなかったことを型で表して返すのは、そのimplブロックがどの型の計測にも入らないためである。
//! 黙って対象から外すと、そのメソッドが数えられないまま検査が通り、通ったことを誰も疑えない。

use std::path::PathBuf;

use super::type_location::型の所在;

pub enum 実装ブロックの引き当て {
    所在が決まった(型の所在),
    定義の候補を1つに絞れない(定義の候補が複数ある実装ブロック),
}

/// 同じ名前の定義が同じ近さで2つ以上あり、どの型のimplか決められなかった1件。
pub struct 定義の候補が複数ある実装ブロック {
    pub ファイル: PathBuf,
    pub 型名: String,
    候補一覧: Vec<型の所在>,
}

impl 定義の候補が複数ある実装ブロック {
    pub fn 生成する(ファイル: PathBuf, 型名: String, 候補一覧: Vec<型の所在>) -> Self {
        Self {
            ファイル, 型名, 候補一覧
        }
    }

    pub fn 候補の綴り(&self) -> String {
        self.候補一覧.iter().map(型の所在::to_string).collect::<Vec<String>>().join(" / ")
    }
}
