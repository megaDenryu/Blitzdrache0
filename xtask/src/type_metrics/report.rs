//! 型計測の一覧を上位から順にテキスト出力する。

use std::path::PathBuf;

use super::metrics::{型計測, 走査範囲の型計測};

pub fn 上位を表示する(計測: &走査範囲の型計測, 表示件数: usize) {
    let 一覧 = &計測.型ごとの計測一覧;
    println!("[xtask] 型単位の負債計測: implの分散ファイル数 -> 宣言の件数 -> メソッド総数 の順で降順に並べる");
    println!("[xtask] 型は定義ファイルと型名の組で識別する。同じ名前の型が別の場所にあれば別々に数える");
    println!("[xtask] 宣言の件数は、構造体ならフィールド数、列挙なら選択肢の数である(選択肢が持つフィールドは数えない)");
    println!("[xtask] 計測した型{}件のうち上位{}件を表示する", 一覧.len(), 表示件数.min(一覧.len()));
    for (順位, 計測) in 一覧.iter().take(表示件数).enumerate() {
        println!("{:>3}. {} : {}", 順位 + 1, 計測.所在, 分量の文字列(計測));
    }
    宣言が1つに決まらない所在を表示する(計測);
    引き当てられなかった実装ブロックを表示する(計測);
}

/// 計測から除いたGraphiteの生成物の件数と名前。0件でも1行目は書き、除いた生成物が無かったことを見せる。
/// 件数を黙って伏せると、上の一覧が走査範囲の全部を数えたものだと読み手が誤って受け取る。
pub fn 除いた生成物を表示する(除いた生成物一覧: &[PathBuf]) {
    println!("[xtask] Graphiteの生成物{}件を計測から外した(先頭の見出しと生成元の宣言が結び付いたファイルだけを外す)", 除いた生成物一覧.len());
    for パス in 除いた生成物一覧 {
        println!("     対象外: {}", パス.display());
    }
}

/// 定義を1つに絞れなかったimplブロックは、どの型の計測にも入っていない。件数を黙って伏せると、
/// 上の一覧が走査範囲の全部を数えたものだと読み手が誤って受け取る。
fn 引き当てられなかった実装ブロックを表示する(計測: &走査範囲の型計測) {
    let 一覧 = &計測.定義の候補を1つに絞れなかった実装ブロック一覧;
    println!("[xtask] 定義を1つに絞れず計測へ入れられなかったimplブロック: {}件", 一覧.len());
    for 実装ブロック in 一覧 {
        println!("     {}: 実装対象「{}」の候補が {}", 実装ブロック.ファイル.display(), 実装ブロック.型名, 実装ブロック.候補の文字列());
    }
}

/// 同じ所在に定義行が複数ある型は、宣言の種別も件数も1つに決まらない。件数を伏せると、上の一覧の
/// 宣言の欄がどれも確定した数だと読み手が誤って受け取る。
fn 宣言が1つに決まらない所在を表示する(計測: &走査範囲の型計測) {
    let 一覧: Vec<&型計測> = 計測.型ごとの計測一覧.iter().filter(|計測| 計測.宣言.定義の件数() > 1).collect();
    println!("[xtask] 同じファイルに同名の定義が複数あり宣言の分量が1つに決まらない型: {}件", 一覧.len());
    for 計測 in 一覧 {
        println!("     {}: {}", 計測.所在, 計測.宣言.文字列());
    }
}

fn 分量の文字列(計測: &型計測) -> String {
    let 宣言の文字列 = 計測.宣言.文字列();
    format!("impl分散{}ファイル / {宣言の文字列} / メソッド{}", 計測.実装ファイル一覧.len(), 計測.メソッド総数)
}
