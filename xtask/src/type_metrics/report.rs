//! 型計測の一覧を上位から順にテキスト出力する。

use super::metrics::型計測;

pub fn 上位を表示する(一覧: &[型計測], 表示件数: usize) {
    println!("[xtask] 型単位の負債計測: implの分散ファイル数 -> フィールド数 -> メソッド総数 の順で降順に並べる");
    println!("[xtask] 計測した型{}件のうち上位{}件を表示する", 一覧.len(), 表示件数.min(一覧.len()));
    for (順位, 計測) in 一覧.iter().take(表示件数).enumerate() {
        println!(
            "{:>3}. {} : impl分散{}ファイル / フィールド{} / メソッド{}",
            順位 + 1,
            計測.型名,
            計測.実装ファイル一覧.len(),
            計測.フィールド数,
            計測.メソッド総数
        );
        match &計測.定義ファイル {
            Some(パス) => println!("     定義: {}", パス.display()),
            None => println!("     定義: 走査範囲に構造体・列挙の定義行が見つからない"),
        }
    }
}
