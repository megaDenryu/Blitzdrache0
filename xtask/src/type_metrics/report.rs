//! 型計測の一覧を上位から順にテキスト出力する。

use super::metrics::{型計測, 走査範囲の型計測};

pub fn 上位を表示する(計測: &走査範囲の型計測, 表示件数: usize) {
    let 一覧 = &計測.型ごとの計測一覧;
    println!("[xtask] 型単位の負債計測: implの分散ファイル数 -> 宣言の件数 -> メソッド総数 の順で降順に並べる");
    println!("[xtask] 型は定義ファイルと型名の組で識別する。同じ名前の型が別の場所にあれば別々に数える");
    println!("[xtask] 宣言の件数は、構造体ならフィールド数、列挙なら枝の数である(枝が持つフィールドは数えない)");
    println!("[xtask] 計測した型{}件のうち上位{}件を表示する", 一覧.len(), 表示件数.min(一覧.len()));
    for (順位, 計測) in 一覧.iter().take(表示件数).enumerate() {
        println!("{:>3}. {} : {}", 順位 + 1, 計測.所在, 分量の綴り(計測));
    }
    引き当てられなかった実装ブロックを表示する(計測);
}

/// 定義を1つに絞れなかったimplブロックは、どの型の計測にも入っていない。件数を黙って伏せると、
/// 上の一覧が走査範囲の全部を数えたものだと読み手が誤って受け取る。
fn 引き当てられなかった実装ブロックを表示する(計測: &走査範囲の型計測) {
    let 一覧 = &計測.定義の候補を1つに絞れなかった実装ブロック一覧;
    println!("[xtask] 定義を1つに絞れず計測へ入れられなかったimplブロック: {}件", 一覧.len());
    for 実装ブロック in 一覧 {
        println!(
            "     {}: 実装対象「{}」の候補が {}",
            実装ブロック.ファイル.display(),
            実装ブロック.型名,
            実装ブロック.候補の綴り()
        );
    }
}

fn 分量の綴り(計測: &型計測) -> String {
    let 宣言の綴り = match &計測.宣言 {
        Some(分量) => format!("{}{}", 分量.指標名(), 分量.件数()),
        None => "宣言なし".to_string(),
    };
    format!(
        "impl分散{}ファイル / {宣言の綴り} / メソッド{}",
        計測.実装ファイル一覧.len(),
        計測.メソッド総数
    )
}
