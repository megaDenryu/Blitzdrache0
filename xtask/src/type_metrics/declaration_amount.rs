//! 型の宣言そのものが持つ分量。構造体はフィールドの数、列挙は枝の数であり、この2つは別の指標である。
//!
//! 列挙の枝が持つ名前付きフィールドは数えない。型付きエラーには破られた不変条件を書くことを規約が
//! 求めるため、枝の中身の合計を上限にすると、規約に従うほど数が増えて検査が落ちる。責務の集中を
//! 測る指標としては逆向きになる。1つの数へ混ぜないのは、台帳を読む人がどちらの数か判断できなくなるためである。

#[derive(Clone, Copy)]
pub enum 宣言の分量 {
    構造体のフィールド数(usize),
    列挙の枝数(usize),
}

impl 宣言の分量 {
    pub fn 件数(&self) -> usize {
        match self {
            Self::構造体のフィールド数(件数) | Self::列挙の枝数(件数) => *件数,
        }
    }

    /// 表示と食い違いの説明で使う指標の呼び名。数の意味を綴りへ載せる唯一の場所である。
    pub fn 指標名(&self) -> &'static str {
        match self {
            Self::構造体のフィールド数(_) => "フィールド数",
            Self::列挙の枝数(_) => "枝数",
        }
    }

    pub fn 同じ種別か(&self, 相手: &Self) -> bool {
        matches!(
            (self, 相手),
            (Self::構造体のフィールド数(_), Self::構造体のフィールド数(_)) | (Self::列挙の枝数(_), Self::列挙の枝数(_))
        )
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn 種別ごとに指標の呼び名が変わる() {
        assert_eq!(宣言の分量::構造体のフィールド数(3).指標名(), "フィールド数");
        assert_eq!(宣言の分量::列挙の枝数(3).指標名(), "枝数");
    }

    #[test]
    fn 件数が同じでも種別が違えば別の指標とみなす() {
        assert_eq!(宣言の分量::列挙の枝数(3).件数(), 3);
        assert!(!宣言の分量::構造体のフィールド数(3).同じ種別か(&宣言の分量::列挙の枝数(3)));
        assert!(宣言の分量::列挙の枝数(3).同じ種別か(&宣言の分量::列挙の枝数(9)));
    }
}
