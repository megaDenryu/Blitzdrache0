//! 1つの所在(定義ファイルと型名の組)に現れた型定義の一覧。走査が同じ所在の定義行を何件見たかを保持する。
//!
//! 一覧で持つのは、同じファイルの中で`#[cfg]`により切り替わる同名の定義が2件以上並ぶためである。
//! そこで後から現れた定義の分量だけを残すと、40フィールドの定義が3フィールドの定義に隠れ、
//! 閾値の検査をすり抜ける。走査は`#[cfg]`のどちらの構成で数えるかを決められないため、
//! 決められないことをこの型が保持し、隠さずに呼び出し側へ渡す。
//! 参照: `conform/type_metrics_ledger`が、隠れると困る場面でだけ違反として報告する。

use super::declaration_amount::宣言の分量;

#[derive(Clone)]
pub struct 所在に現れた宣言一覧 {
    分量一覧: Vec<宣言の分量>,
}

impl 所在に現れた宣言一覧 {
    pub fn 空で始める() -> Self {
        Self { 分量一覧: Vec::new() }
    }

    pub fn ただ1つの定義から生成する(分量: 宣言の分量) -> Self {
        Self { 分量一覧: vec![分量] }
    }

    pub fn 宣言を取り込む(&mut self, 分量: 宣言の分量) {
        self.分量一覧.push(分量);
    }

    pub fn 定義の件数(&self) -> usize {
        self.分量一覧.len()
    }

    /// 定義がちょうど1件のときだけ、その分量を返す。2件以上あるときに1件を選んで返すことはしない。
    pub fn ただ1つの宣言(&self) -> Option<宣言の分量> {
        let [唯一の定義] = self.分量一覧.as_slice() else {
            return None;
        };
        Some(*唯一の定義)
    }

    pub fn 分量一覧(&self) -> &[宣言の分量] {
        &self.分量一覧
    }

    /// 並べ替えの比較鍵が使う件数。定義が複数あるときは最も大きい件数を採り、大きい定義を後ろへ沈めない。
    pub fn 最も大きい件数(&self) -> usize {
        self.分量一覧.iter().map(宣言の分量::件数).max().unwrap_or(0)
    }

    /// 表示と違反の説明で使う綴り。定義が複数あるなら、どれか1つへ寄せずに全部を並べる。
    pub fn 綴り(&self) -> String {
        match self.分量一覧.as_slice() {
            [] => "宣言なし".to_string(),
            [唯一の定義] => format!("{}{}", 唯一の定義.指標名(), 唯一の定義.件数()),
            複数の定義 => format!("定義が{}件({})", 複数の定義.len(), self.分量ごとの綴り().join(" / ")),
        }
    }

    fn 分量ごとの綴り(&self) -> Vec<String> {
        self.分量一覧.iter().map(|分量| format!("{}{}", 分量.指標名(), 分量.件数())).collect()
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn 定義が2件あるなら1つの宣言へ寄せず両方を綴る() {
        let mut 一覧 = 所在に現れた宣言一覧::ただ1つの定義から生成する(宣言の分量::構造体のフィールド数(40));
        一覧.宣言を取り込む(宣言の分量::構造体のフィールド数(3));
        assert_eq!(一覧.定義の件数(), 2);
        assert!(一覧.ただ1つの宣言().is_none());
        assert_eq!(一覧.最も大きい件数(), 40);
        assert_eq!(一覧.綴り(), "定義が2件(フィールド数40 / フィールド数3)");
    }

    #[test]
    fn 定義が無いときと1件のときの綴りを分ける() {
        assert_eq!(所在に現れた宣言一覧::空で始める().綴り(), "宣言なし");
        assert_eq!(所在に現れた宣言一覧::ただ1つの定義から生成する(宣言の分量::列挙の枝数(2)).綴り(), "枝数2");
    }
}
