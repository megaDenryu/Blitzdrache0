//! 1つの条件で本番の描画経路を1回走らせるための起動指定。受け取るのはシーンと枚数と条件ごとの選択肢、
//! 返すのは実行環境へ渡す起動指定である。起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! 時間再構成と自動露出をここで外すのは、どちらもフレームをまたいで値を持ち越すためである。持ち越しがあると、
//! 同一起動の中で撮った2枚が一致することを読み戻しの決定性の根拠にできない。

use crate::acceptance::{アプリの起動指定, 描画フレーム数, 検収シーン名};

/// どの条件でも外すもの。条件ごとの指定より先に足して、条件の側が消せないようにする。
const 持ち越しを外す選択肢: [&str; 2] = ["--no-taa", "--no-auto-exposure"];

pub(crate) fn 起動指定を組み立てる(
    シーン名: 検収シーン名, 枚数: 描画フレーム数, 条件ごとの選択肢: &[&str]
) -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(シーン名, 枚数)
        .選択肢をまとめて足す(&持ち越しを外す選択肢)
        .選択肢をまとめて足す(条件ごとの選択肢)
}
