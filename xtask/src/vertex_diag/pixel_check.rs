//! 2枚の読み戻し画像の食い違いを数える工程。受け取るのは2つの実行結果、返すのは食い違った画素の数と最大の差である。
//!
//! 影の輪郭が動けばここに現れる。構図が影で覆われているためである。
//! 数えるのは食い違った画素の数と最大の差だけであり、食い違いが輪郭に限られているかは判定しない。
//! 上限との比較は幾何同値性の検証ではなく、既知の実装状態からの回帰検知である(理由は`vertex_diag`の冒頭)。

use crate::acceptance::{判定の名前, 判定の破れ, 読み戻し画像};

const 二条件の読み戻し寸法: 判定の名前 = 判定の名前::定数から生成する("2条件の読み戻し寸法");

pub(super) struct 画素の食い違い {
    食い違い画素数: usize,
    全画素数: usize,
    最大チャンネル差: u8,
}

impl 画素の食い違い {
    /// 食い違った画素が全画素の割合の上限に収まっているかを確かめる。上限は割合の逆数で受け取る。
    pub(super) fn 上限内か確かめる(&self, 対象: &str, 許す割合の逆数: usize) -> Result<(), 判定の破れ> {
        self.判定名(対象).上限を課す(self.食い違い画素数, self.全画素数 / 許す割合の逆数)
    }

    pub(super) fn 要約(&self) -> String {
        format!(
            "全{}画素中{}画素で食い違い(最大チャンネル差{})",
            self.全画素数, self.食い違い画素数, self.最大チャンネル差
        )
    }

    /// 名前へ全画素数と最大チャンネル差を入れるのは、上限を超えた実行の文面だけで食い違いの大きさが読めるようにするためである。
    fn 判定名(&self, 対象: &str) -> 判定の名前 {
        判定の名前::組み立てた綴りから生成する(format!(
            "{対象}の食い違った画素数(全{}画素中、最大チャンネル差{})",
            self.全画素数, self.最大チャンネル差
        ))
    }
}

pub(super) fn 数える(粗い: &読み戻し画像, 細かい: &読み戻し画像) -> Result<画素の食い違い, 判定の破れ> {
    二条件の読み戻し寸法.綴りの一致を課す(&細かい.寸法の綴り(), &粗い.寸法の綴り())?;
    let 全画素数 = 粗い.画素数();
    let mut 食い違い画素数 = 0usize;
    let mut 最大チャンネル差 = 0u8;
    for (粗い画素, 細かい画素) in 粗い.画素列().zip(細かい.画素列()) {
        let 差 = 粗い画素
            .iter()
            .zip(細かい画素.iter())
            .map(|(粗い成分, 細かい成分)| 粗い成分.abs_diff(*細かい成分))
            .max()
            .unwrap_or(0);
        if 差 > 0 {
            食い違い画素数 += 1;
            最大チャンネル差 = 最大チャンネル差.max(差);
        }
    }
    Ok(画素の食い違い {
        食い違い画素数,
        全画素数,
        最大チャンネル差,
    })
}
