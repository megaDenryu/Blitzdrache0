//! 2つの診断世界の終了時報告を突き合わせる判定。受け取るのは粗い側と細かい側の計数報告、
//! 返すのは距離区分別の可視数と、投入インデックス数の差から導いた群の個体数である。
//!
//! 投入インデックス数は地形の寄与も含むため、比をそのまま取っても16にはならない。
//! 地形は2つの世界で同じであるから、差はすべて群の寄与であり、1体あたりの増分で割り切れなければならない。
//! 割り切れないなら、描いた個体か段が2つの世界で食い違っている。

use crate::report_parse::{全パスを並べる, 計数報告};

/// 投入インデックス数を除くパス別の計数と、可視個体の選別の距離区分別の可視数が一致することを確かめる。
/// 一致した距離区分別の可視数を返す。
pub(super) fn 計数の一致を検査する(粗い: &計数報告, 細かい: &計数報告) -> Result<Vec<u64>, String> {
    for ((名前, 粗い側), (_, 細かい側)) in 全パスを並べる(粗い).into_iter().zip(全パスを並べる(細かい)) {
        let 粗い並び = [粗い側.発行数, 粗い側.候補数, 粗い側.可視数, 粗い側.個体数];
        let 細かい並び = [細かい側.発行数, 細かい側.候補数, 細かい側.可視数, 細かい側.個体数];
        if 粗い並び != 細かい並び || 粗い側.段別個体数 != 細かい側.段別個体数 {
            return Err(format!(
                "{名前}の描画発行の計数が食い違う(粗い側は発行と候補と可視と個体が{粗い並び:?}で段別{:?}、細かい側は{細かい並び:?}で段別{:?})",
                粗い側.段別個体数, 細かい側.段別個体数
            ));
        }
    }
    let (粗い可視数, 細かい可視数) = (&粗い.可視個体の選別.距離区分別の可視数, &細かい.可視個体の選別.距離区分別の可視数);
    if 粗い可視数 != 細かい可視数 {
        return Err(format!("距離区分別の可視数が食い違う(粗い側{粗い可視数:?}・細かい側{細かい可視数:?})"));
    }
    Ok(粗い可視数.clone())
}

/// 距離区分ごとに、投入インデックス数の差から群の個体数を導く。差が1体あたりの増分で割り切れなければ失敗させる。
pub(super) fn 群の個体数を導く(粗い: &計数報告, 細かい: &計数報告, 一体あたりの増分: u64) -> Result<Vec<u64>, String> {
    let mut 個体数一覧 = Vec::with_capacity(粗い.距離区分別のシャドウ.len());
    for (番号, (粗い側, 細かい側)) in 粗い.距離区分別のシャドウ.iter().zip(&細かい.距離区分別のシャドウ).enumerate()
    {
        let (粗い数, 細かい数) = (粗い側.投入インデックス数, 細かい側.投入インデックス数);
        if 細かい数 < 粗い数 || (細かい数 - 粗い数) % 一体あたりの増分 != 0 {
            return Err(format!(
                "距離区分{番号}の投入インデックス数の差が1体あたりの増分{一体あたりの増分}の倍数でない(粗い側{粗い数}・細かい側{細かい数})"
            ));
        }
        個体数一覧.push((細かい数 - 粗い数) / 一体あたりの増分);
    }
    Ok(個体数一覧)
}
