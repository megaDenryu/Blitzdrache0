//! 頂点量の診断の検収が返す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。
//! 様式は`acceptance/error.rs`と`depth_prepass_cost/error.rs`に倣う。
//!
//! 検収の器の破れと判定の破れを枝で内包するのは、この入口が起動と読み取りと判定を一続きに通すためである。
//! 3つを別の型で返すと、通す側が段ごとに変換を書くことになる。
//!
//! アセットの生成をここが持つのは、それが判定でも報告の読み取りでもないためである。
//! 診断世界を2つ焼くため、どちらの世界で焼けなかったかを枝が名指す。
//! 人が読む1文へ写すのは`display`が持つ。

mod display;

use crate::acceptance::{判定の破れ, 検収エラー};
use crate::asset_generator::世界名;

#[derive(Debug)]
pub(super) enum 頂点量の診断の検収エラー {
    検収の器が破れた(検収エラー),
    判定が破れた(判定の破れ),
    検証用ソースアセットを生成できなかった,
    診断世界の実行時アセットを生成できなかった { 世界: 世界名 },
}

impl std::error::Error for 頂点量の診断の検収エラー {}

impl From<検収エラー> for 頂点量の診断の検収エラー {
    fn from(破れ: 検収エラー) -> Self {
        Self::検収の器が破れた(破れ)
    }
}

impl From<判定の破れ> for 頂点量の診断の検収エラー {
    fn from(破れ: 判定の破れ) -> Self {
        Self::判定が破れた(破れ)
    }
}
