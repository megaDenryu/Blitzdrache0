//! 差し替えの前後の3つの要求の判定。受け取るのは差し替えを挟んだ1回の実行、返すのは合否と実測の要約である。
//!
//! 成功の行を数えるのは、絵が動かないことだけでは「差し替えが1度も起きなかった実行」と区別できないためである。
//! 行の綴りは`crates/blitz_app/src/app/hot_reload_apply.rs`の出力と一致させている。

use crate::acceptance::{判定の名前, 判定の破れ, 検収の1回の実行, 検収エラー, 終了時報告, 読み戻し画像};
use crate::report_heading::報告の見出し;

/// 差し替えが成立したときにアプリが1回だけ出す行。
const 差し替え成功の行: 報告の見出し =
    報告の見出し::定数から生成する("[hot-reload] 契約別のシェーダー束でシーンのパイプラインを差し替えた");

/// ちょうど1回であることを求める。0回は監視も交換も起きなかった実行であり、2回以上は書き換えを1度しか行わない
/// 計画と噛み合わない(mtimeの再検知が余分に走っている)。
const 差し替え成功の回数: 判定の名前 =
    判定の名前::定数から生成する("差し替え成功の行の回数(監視・再コンパイル・パイプライン交換が1度ずつ起きたこと)");

pub(super) fn 差し替えを検査する(
    差し替え前: &読み戻し画像, 差し替え後: &検収の1回の実行
) -> Result<String, 検収エラー> {
    let 成功回数 = 差し替え成功の回数を数える(差し替え後.報告())?;
    let 画素数 = 画像が一致することを確かめる(差し替え前, 差し替え後.画像())?;
    Ok(format!(
        "差し替え成功{成功回数}回・validationの指摘0件・差し替えの前後の{画素数}画素がバイト一致"
    ))
}

fn 差し替え成功の回数を数える(報告: &終了時報告) -> Result<usize, 判定の破れ> {
    let 回数 = 報告.見出しで始まる行の一覧(&差し替え成功の行).len();
    差し替え成功の回数.一致を課す(回数, 1)?;
    Ok(回数)
}

/// 遠方環境の契約が選ぶ画素段は書き換えていないため、差し替えの前後で1バイトも動いてはならない。
fn 画像が一致することを確かめる(前: &読み戻し画像, 後: &読み戻し画像) -> Result<usize, 判定の破れ> {
    判定の名前::定数から生成する("差し替えの前後の読み戻し画像の寸法").綴りの一致を課す(&後.寸法の綴り(), &前.寸法の綴り())?;
    let 違う画素数 = 前.画素列().zip(後.画素列()).filter(|(前の画素, 後の画素)| 前の画素 != 後の画素).count();
    判定の名前::定数から生成する(
        "差し替えの前後で変わった画素(遠方環境の契約が選ぶ画素段は書き換えていないため1画素も動いてはならない)",
    )
    .零件であることを課す(違う画素数)?;
    Ok(前.画素数())
}
