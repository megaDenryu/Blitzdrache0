//! 差し替えの前後の3つの要求の判定。受け取るのは差し替えを挟んだ1回の実行、返すのは合否と実測の要約である。
//!
//! 成功の行を数えるのは、絵が動かないことだけでは「差し替えが1度も起きなかった実行」と区別できないためである。
//! 行の綴りは`crates/blitz_app/src/app/hot_reload_apply.rs`の出力と一致させている。

use super::run::差し替えを挟んだ実行;
use crate::acceptance::読み戻し画像;

/// 差し替えが成立したときにアプリが1回だけ出す行。
const 差し替え成功の行: &str = "[hot-reload] 契約別のシェーダー束でシーンのパイプラインを差し替えた";

pub(super) fn 差し替えを検査する(実行: &差し替えを挟んだ実行) -> Result<String, String> {
    let 成功回数 = 差し替え成功の回数を数える(実行.報告.本文())?;
    実行.報告.検証層の指摘が零件であることを確かめる()?;
    let 画素数 = 画像が一致することを確かめる(&実行.差し替え前, &実行.差し替え後)?;
    Ok(format!(
        "差し替え成功{成功回数}回・validationの指摘0件・差し替えの前後の{画素数}画素がバイト一致"
    ))
}

/// ちょうど1回であることを求める。0回は監視も交換も起きなかった実行であり、2回以上は書き換えを1度しか行わない
/// 計画と噛み合わない(mtimeの再検知が余分に走っている)。
fn 差し替え成功の回数を数える(標準出力: &str) -> Result<usize, String> {
    let 回数 = 標準出力.lines().filter(|行| 行.contains(差し替え成功の行)).count();
    if 回数 != 1 {
        return Err(format!(
            "差し替え成功の行が{回数}回だった(ちょうど1回を求める)。監視・再コンパイル・パイプライン交換のどこかが起きていない"
        ));
    }
    Ok(回数)
}

/// 遠方環境の契約が選ぶ画素段は書き換えていないため、差し替えの前後で1バイトも動いてはならない。
fn 画像が一致することを確かめる(前: &読み戻し画像, 後: &読み戻し画像) -> Result<usize, String> {
    if !前.寸法が同じか(後) {
        return Err(format!(
            "差し替えの前後で読み戻し画像の寸法が違う: 前{}、後{}",
            前.寸法の綴り(),
            後.寸法の綴り()
        ));
    }
    let 違う画素数 = 前.画素列().zip(後.画素列()).filter(|(前の画素, 後の画素)| 前の画素 != 後の画素).count();
    if 違う画素数 != 0 {
        return Err(format!(
            "差し替えの前後で{違う画素数}画素が変わった(遠方環境の契約が選ぶ画素段は書き換えていないため1画素も動いてはならない)"
        ));
    }
    Ok(前.画素数())
}
