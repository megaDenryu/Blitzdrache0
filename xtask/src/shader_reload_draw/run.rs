//! 差し替えを挟む1回の起動の指定と、その起動が書き出す2枚の名前。受け取るのは監視先のエントリファイル、
//! 返すのは実行環境へ渡す起動指定である。起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! 起動が1回なのがこの検収の要点である。アプリが計画にしたがって差し替え前の絵を`_before`の名前で書き出し、
//! 監視先のシェーダーを書き換え、最終フレームで差し替え後の絵を書き出す。2回起動すると、同じプロセスの中で
//! パイプラインが入れ替わったことを見たことにならない。
//!
//! 昼を選ぶのは、大気から焼いた遠方環境が最も明るく、間接光が板の画素へ強く出る時刻だからである。間接光が0に近い
//! 時刻では、誤って定数近似の画素段が載っても絵が動かず、画像のバイト一致が判定の意味を失う。
//! ポスト処理を通したままにするのは、明るさの圧縮が無いと昼の板が飽和して同じ理由で差が消えるためである。

use std::path::{Path, PathBuf};

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収の実行名, 検収エラー, 検収シーン名,
};
use crate::verify::検証の出力ルート;

/// 0.5秒ごとの確認・3本の再コンパイル・全シーンキーのパイプライン再構築を書き換えから最終フレームまでに収めるため、
/// 既存の読み戻し検収より長く回す。
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(300);
const シーンの綴り: &str = "indirect_probe";
const シーン名: 検収シーン名 = 検収シーン名::生成する(シーンの綴り);
/// 昼の一日内秒。太陽が高く、大気から焼いた遠方環境が最も明るくなる。
const 昼の一日内秒: &str = "43200";
const 差し替えを起こす選択肢: [&str; 3] = ["--no-sky", "--shader-reload", "--report-memory"];

/// 最終フレームの書き出しの基準名。アプリはこの名前をそのまま使う。
pub(super) const 差し替え後の実行名: 検収の実行名 = 検収の実行名::定数から生成する(シーンの綴り);
/// 差し替え前の書き出しの基準名。アプリが最終フレームの名前へ`_before`を足して書き出す。
/// 綴りをここで組むのは、書く側と読む側の食い違いが「ファイルが無い」という遠い失敗に化けるためである。
pub(super) const 差し替え前の実行名: 検収の実行名 = 検収の実行名::定数から生成する("indirect_probe_before");

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::パスから生成する(
            検証の出力ルート::既定().名前が指す置き場(crate::compile_assets::板の世界の実行時形式の置き場),
        ),
        出力ディレクトリ,
    )
}

pub(super) fn 起動指定を組み立てる(監視先: &Path) -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数)
        .値を持つ選択肢を足す("--time-of-day", 昼の一日内秒)
        .選択肢をまとめて足す(&差し替えを起こす選択肢)
        .パスを値に持つ選択肢を足す("--shader-source", 監視先)
}
