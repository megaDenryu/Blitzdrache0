//! 場所巡りの通しの検収エラーを人が読む1文へ写すトレイト実装。枝ごとに、どの前提がどう破れたかを出す。
//! 実装を型の定義と分けるのは、外部トレイトの実装が型自身の持ち物とは別の軸であるためである。

use std::fmt;

use super::場所巡りの通しの検収エラー;

impl fmt::Display for 場所巡りの通しの検収エラー {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::検収の器が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::判定が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::ソースの生成が失敗した(破れ) | Self::実行時形式の焼き付けが失敗した(破れ) => {
                write!(書き手, "{破れ}")
            }
            Self::検収用のルートを消せなかった { パス, 誤り } => {
                write!(書き手, "{}を消せなかった: {誤り}", パス.display())
            }
            Self::ディレクトリを開けなかった { パス, 誤り } | Self::ファイルを開けなかった { パス, 誤り } => {
                write!(書き手, "{}を開けなかった: {誤り}", パス.display())
            }
            Self::ディレクトリの走査に失敗した { パス, 誤り } => {
                write!(書き手, "{}の走査に失敗した: {誤り}", パス.display())
            }
            Self::相対パスを求められなかった { パス } => {
                write!(書き手, "{}の相対化に失敗した", パス.display())
            }
            Self::ファイルを読めなかった { パス, 誤り } => {
                write!(書き手, "{}を読めなかった: {誤り}", パス.display())
            }
        }
    }
}
