//! アセットコンパイラの標準出力から、検収が読む2つの行を取り出す型。受け取るのは取り込んだ標準出力、
//! 返すのは遠景の沈みの行と個体数の行である。
//!
//! 2つを1つの型が持つのは、どちらも同じ1回の焼き付けの標準出力からしか読めず、読み落としを同じ場所で
//! 拒みたいためである。行を探す綴りを呼び出し側へ散らすと、片方だけが静かに読めなくなる。
//!
//! 注意: 個体数の行の綴りは書き手(`crates/blitz_asset_compiler/examples/compile_assets/instance_tally.rs`)にも
//! 同じものがある。両側にあることは`cargo xtask conform`の綴りの契約の検査が守る。

use crate::acceptance::{判定の名前, 検収の実行名, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

/// 遠景の沈みの統計を持つ行を見分ける語。
const 遠景の沈みの語: &str = "遠景沈み";

/// 個体数の合計の欄の綴り。等号まで含めて持つのは、鍵の直前に空白を置かない行があるためである。
const 合計の欄の綴り: &str = "個体数の合計=";
const 合計の欄の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する(合計の欄の綴り);

const 合計の欄の行: 判定の名前 = 判定の名前::定数から生成する("アセットコンパイラの報告の個体数の合計を持つ行");

pub(super) struct コンパイルの報告 {
    報告: 終了時報告,
    遠景の沈みの行: Option<String>,
}

impl コンパイルの報告 {
    /// 遠景の沈みの行は、遠景を焼かない世界では出ないため値なしを許す。個体数の行の不在は
    /// 読み取りの地点で失敗にする。散布が効いていることは生成物の中身に現れず、この行が唯一の証拠である。
    pub(super) fn 標準出力から読む(標準出力: String) -> Self {
        let 遠景の沈みの行 = 標準出力.lines().find(|行| 行.contains(遠景の沈みの語)).map(str::to_string);
        Self {
            報告: 終了時報告::取り込む(&検収の実行名::定数から生成する("map_asset_compile"), 標準出力, String::new()),
            遠景の沈みの行,
        }
    }

    pub(super) fn 遠景の沈みの行(&self) -> Option<&String> {
        self.遠景の沈みの行.as_ref()
    }

    /// 合計の欄を持つ行から数を読む。コンパイラは自分の見出しで始まる行を何本も出すため、
    /// 見出しの最初の1行でなく合計の欄を持つ行を探す。
    pub(super) fn 個体数の合計を読む(&self) -> Result<usize, 検収エラー> {
        let 行一覧 = self.報告.見出しで始まる行の一覧(&報告の見出し::定数から生成する("[compile_assets] "));
        let 行 = 行一覧
            .iter()
            .find(|行| 行.原文().contains(合計の欄の綴り))
            .ok_or_else(|| 合計の欄の行.あるはずのものが無い破れ())?;
        行.鍵に結ばれた数(&合計の欄の鍵, 鍵に値が結ばれる形::この綴りに続く数字の並びが値である)
    }
}
