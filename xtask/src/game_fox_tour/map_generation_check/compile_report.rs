//! アセットコンパイラの標準出力から、検収が読む4つの行を取り出す型。受け取るのは取り込んだ標準出力、
//! 返すのは遠景の沈みの行と、実行時カタログから数えた個体数と、焼く工程が置いた個体数と、据え置いたチャンク数である。
//!
//! 4つを1つの型が持つのは、どれも同じ1回の焼き付けの標準出力からしか読めず、読み落としを同じ場所で
//! 拒みたいためである。行を探す綴りを呼び出し側へ散らすと、1つだけが静かに読めなくなる。
//!
//! 注意: 個体数の行の綴りは書き手(`crates/blitz_asset_compiler/examples/compile_assets/instance_tally.rs`)にも、
//! 置いた個体の行の綴りは書き手(`crates/blitz_asset_compiler/examples/compile_assets/placed_instance_tally.rs`)にも、
//! 据え置いたチャンク数の綴りは書き手(`crates/blitz_asset_compiler/src/generation_ledger/rebake_tally.rs`)にも
//! 同じものがある。両側にあることは`cargo xtask conform`の綴りの契約の検査が守る。

use crate::acceptance::{判定の名前, 検収の実行名, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

/// 遠景の沈みの統計を持つ行を見分ける語。
const 遠景の沈みの語: &str = "遠景沈み";

/// 個体数の合計の欄の綴り。等号まで含めて持つのは、鍵の直前に空白を置かない行があるためである。
const 合計の欄の綴り: &str = "個体数の合計=";
const 合計の欄の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する(合計の欄の綴り);

const 合計の欄の行: 判定の名前 = 判定の名前::定数から生成する("アセットコンパイラの報告の個体数の合計を持つ行");

/// 焼く工程が置いた個体の合計の欄の綴り。実行時カタログから数えた合計の欄とは別の綴りにしてある。
/// 同じ綴りを含めると、行を探す照合が先に出たほうの行を拾って、2つの数が同じ1行から読まれる。
const 置いた合計の欄の綴り: &str = "置いた個体の合計=";
const 置いた合計の欄の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する(置いた合計の欄の綴り);
const 置いた合計の欄の行: 判定の名前 = 判定の名前::定数から生成する("アセットコンパイラの報告の置いた個体の合計を持つ行");

/// 据え置いたチャンク数の欄の綴り。据え置いた対象は焼く工程を通らず置いた個体を数えないため、
/// 2つの個体数の一致を課してよいかをこの数が決める。
const 据え置きの欄の綴り: &str = "据え置いたチャンク数=";
const 据え置きの欄の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する(据え置きの欄の綴り);
const 据え置きの欄の行: 判定の名前 = 判定の名前::定数から生成する("アセットコンパイラの報告の据え置いたチャンク数を持つ行");

pub(super) struct コンパイルの報告 {
    報告: 終了時報告,
    遠景の沈みの行: Option<String>,
}

impl コンパイルの報告 {
    /// 遠景の沈みの行は、遠景を焼かない世界では出ないため値なしを許す。個体数の行の不在は
    /// 読み取りの地点で失敗にする。散布が効いていることは生成物の中身に現れず、この行が唯一の証拠である。
    pub(super) fn 標準出力から読む(標準出力: String) -> Self {
        let 遠景の沈みの行 = 標準出力.lines().find(|行| 行.contains(遠景の沈みの語)).map(str::to_string);
        Self {
            報告: 終了時報告::取り込む(&検収の実行名::定数から生成する("map_asset_compile"), 標準出力, String::new()),
            遠景の沈みの行,
        }
    }

    pub(super) fn 遠景の沈みの行(&self) -> Option<&String> {
        self.遠景の沈みの行.as_ref()
    }

    /// 合計の欄を持つ行から数を読む。コンパイラは自分の見出しで始まる行を何本も出すため、
    /// 見出しの最初の1行でなく合計の欄を持つ行を探す。
    pub(super) fn 個体数の合計を読む(&self) -> Result<usize, 検収エラー> {
        self.欄を持つ行から数を読む(合計の欄の綴り, &合計の欄の鍵, &合計の欄の行)
    }

    /// 焼く工程が置いた個体の合計を読む。実行時カタログから数えた合計と別の地点で数えた値であり、
    /// 2つの食い違いが群の描画対象への載せ漏れを表す。
    pub(super) fn 置いた個体の合計を読む(&self) -> Result<usize, 検収エラー> {
        self.欄を持つ行から数を読む(置いた合計の欄の綴り, &置いた合計の欄の鍵, &置いた合計の欄の行)
    }

    /// 据え置いたチャンク数を読む。0本でない実行では、焼く工程を通らなかった対象の個体が置いた側にだけ現れず、
    /// 2つの個体数は正当に食い違う。
    pub(super) fn 据え置いたチャンク数を読む(&self) -> Result<usize, 検収エラー> {
        self.欄を持つ行から数を読む(据え置きの欄の綴り, &据え置きの欄の鍵, &据え置きの欄の行)
    }

    fn 欄を持つ行から数を読む(
        &self, 欄の綴り: &str, 鍵: &報告の行の鍵, 判定名: &判定の名前
    ) -> Result<usize, 検収エラー> {
        let 行一覧 = self.報告.見出しで始まる行の一覧(&報告の見出し::定数から生成する("[compile_assets] "));
        let 行 = 行一覧
            .iter()
            .find(|行| 行.原文().contains(欄の綴り))
            .ok_or_else(|| 判定名.あるはずのものが無い破れ())?;
        行.鍵に結ばれた数(鍵, 鍵に値が結ばれる形::この綴りに続く数字の並びが値である)
    }
}
