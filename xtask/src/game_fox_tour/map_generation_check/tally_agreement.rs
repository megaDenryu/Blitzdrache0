//! 焼く工程が置いた個体の合計と、実行時カタログが持つ個体数の合計の突き合わせ。受け取るのはコンパイルの報告、
//! 返すのは突き合わせの要約である。
//!
//! 2つを比べる網が捕まえるのは、群の描画対象への載せ漏れである。配置は作られたのに描画対象がシーンへ載らないと、
//! カタログの個体数だけが減り、焼く工程が数えた側は減らない。カタログの個体数だけを見ても、その数は載った描画対象から
//! 作られているため、載らなかったものは初めから数の外にあって欠けたことが現れない。
//!
//! 一致を課すのは据え置いたチャンクが0本の実行だけである。据え置いた対象は焼く工程を通らないため置いた個体を1体も
//! 数えず、カタログの側は前回の焼き上がりから写した個体数を持つ。増分が効いた実行でこの2つは正当に食い違う。

use super::super::error::場所巡りの通しの検収エラー;
#[cfg(test)]
mod tally_agreement_tests;

use super::compile_report::コンパイルの報告;
use crate::acceptance::判定の名前;

const 置いた個体とカタログの個体数: 判定の名前 =
    判定の名前::定数から生成する("焼く工程が置いた個体の合計と実行時カタログの個体数の合計");

pub(super) fn 焼く工程とカタログの個体数が一致することを確かめる(
    報告: &コンパイルの報告,
) -> Result<String, 場所巡りの通しの検収エラー> {
    let 据え置いたチャンク数 = 報告.据え置いたチャンク数を読む()?;
    let 置いた合計 = 報告.置いた個体の合計を読む()?;
    let カタログの合計 = 報告.個体数の合計を読む()?;
    if 据え置いたチャンク数 > 0 {
        return Ok(format!(
            "据え置いたチャンクが{据え置いたチャンク数}本あるため個体数の一致は課さない(焼く工程は{置いた合計}体を置き、カタログは{カタログの合計}体を持つ)"
        ));
    }
    置いた個体とカタログの個体数.一致を課す(置いた合計, カタログの合計)?;
    Ok(format!("焼く工程が置いた個体とカタログの個体数がどちらも{置いた合計}体で一致した"))
}
