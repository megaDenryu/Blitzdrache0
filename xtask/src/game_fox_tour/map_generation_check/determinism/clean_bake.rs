//! 検収用のルートを空にしてから1回だけ焼く2つの局面。受け取るのは種と広がりと置き場、返すのは畳んだ値である。
//!
//! 掃除を焼き付けと同じ局面に置くのは、決定性の突き合わせが「増分を無効にした2つの生成」どうしでなければ
//! 空の検査になるためである。掃除を呼び忘れた実行は、焼き直していないファイルを自分自身と比べる。
//!
//! 遠景を焼かない世界では沈みの報告の行が出ない。行の不在をその世界では正しい姿として扱い、焼く世界でだけ不在を失敗にする。

use std::collections::BTreeMap;
use std::path::PathBuf;

use blitz_asset_compiler::{マップ生成の乱数の種, 世界の広がり, 散布の焼き方};

use super::super::super::error::場所巡りの通しの検収エラー;
use super::super::check_root::{検収用のルート, 生成検収の親ディレクトリ};
use super::super::compile_report::コンパイルの報告;

pub(super) fn 掃除してからソースを書き出す(
    種: マップ生成の乱数の種,
    広がり: 世界の広がり,
    ソースルート: &検収用のルート,
) -> Result<BTreeMap<PathBuf, u64>, 場所巡りの通しの検収エラー> {
    ソースルート.掃除する()?;
    ソースルート.既存素材を複写する()?;
    crate::gen_game_map::source_write::ソースルートと広がりを指定して書き出す(種, &ソースルート.ソースルートとして読む(), 広がり)
        .map_err(場所巡りの通しの検収エラー::ソースの生成が失敗した)?;
    ソースルート.場所巡りの生成物を畳む()
}

pub(super) fn 掃除してから実行時形式を焼く(
    親: 生成検収の親ディレクトリ,
    ソースルート: &検収用のルート,
    出力ルート: &検収用のルート,
) -> Result<(BTreeMap<PathBuf, u64>, コンパイルの報告), 場所巡りの通しの検収エラー> {
    出力ルート.掃除する()?;
    let 標準出力 = crate::compile_assets::ルートを名指しして焼き標準出力を返す(
        ソースルート.プロセスへ渡すパス(),
        出力ルート.プロセスへ渡すパス(),
        crate::asset_generator::世界名::場所巡りの世界,
        親.遠景地形の焼き方(),
        // 生成の検収は散布が効いていることを見る側であるため、常に焼く。焼かない側を選ぶのは絵の対照を採る検収だけである。
        散布の焼き方::焼く,
    )
    .map_err(場所巡りの通しの検収エラー::実行時形式の焼き付けが失敗した)?;
    let 報告 = コンパイルの報告::標準出力から読む(標準出力);
    if 親.遠景地形の焼き方().焼くか() && 報告.遠景の沈みの行().is_none() {
        return Err(場所巡りの通しの検収エラー::遠景容量検収が失敗した(
            "遠景沈みの報告行が無い".to_string(),
        ));
    }
    Ok((出力ルート.全ファイルを畳む()?, 報告))
}
