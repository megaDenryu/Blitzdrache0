//! game-fox-tourが遊ぶ出力とリポジトリ内ソースへ書かないことの検査。

use super::{検収用のルート, 生成検収の親ディレクトリ};

#[test]
fn 全ての検収用実行時ルートは遊ぶルートと別である() {
    let 遊ぶ = crate::fox_tour_launch::場所巡りの世界を遊ぶ実行時形式の出力ルート();
    for 検収 in [
        検収用のルート::実行時形式の一度目(生成検収の親ディレクトリ::場所巡り),
        検収用のルート::実行時形式の二度目(生成検収の親ディレクトリ::場所巡り),
        検収用のルート::増分の実行時形式(生成検収の親ディレクトリ::場所巡り),
    ] {
        assert_ne!(検収.プロセスへ渡すパス(), 遊ぶ.プロセスの引数へ渡すディレクトリ());
    }
}

#[test]
fn 全ての検収用ソースルートはリポジトリ内ソースと別である() {
    for 検収 in [
        検収用のルート::ソースの一度目(生成検収の親ディレクトリ::場所巡り),
        検収用のルート::ソースの二度目(生成検収の親ディレクトリ::場所巡り),
        検収用のルート::増分のソース(生成検収の親ディレクトリ::場所巡り),
    ] {
        assert_ne!(検収.プロセスへ渡すパス(), crate::compile_assets::ソースルート());
    }
}
