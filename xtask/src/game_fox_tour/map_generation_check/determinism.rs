//! 同じ種からの2つのクリーンな生成が同じバイト列になることを確かめる工程。受け取るのは種、返すのは突き合わせた本数の要約である。
//!
//! 突き合わせを2段に分けるのは、決定性が破れうる場所が2つあるためである。1つは種から高さを決める計算であり、
//! もう1つは高さ格子からメッシュと高さ場を焼く工程である。前者は2つの別のソースルートへの書き出しどうしを、
//! 後者は同じソースから2つの別の出力ルートへのコンパイルどうしを比べる。
//!
//! 実行時形式の側で2つのソースルートを使わないのは2つの事情による。1つは、実行時カタログがソースの依存一覧を
//! パスの綴りのまま持つため、2つの実行時形式は同じ検収用ソースルートから焼く。
//! もう1つは、この世界がキツネのglTFのように世界のディレクトリの外にあるソースも読むことである。
//! 検収用ソースルートには生成対象以外の既存素材を複写し、生成対象だけを検収用ルートへ生成する。
//!
//! 増分は各ルートを消してから走らせることで無効にする。増分の再実行との突き合わせにすると、焼き直していない
//! ファイルを自分自身と比べることになり空の検査になる。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

use blitz_asset_compiler::{マップ生成の乱数の種, 世界の広がり};

use std::collections::BTreeMap;
use std::path::PathBuf;

use super::super::error::場所巡りの通しの検収エラー;
use super::check_root::{検収用のルート, 生成検収の親ディレクトリ};
use super::digest_compare::畳んだ値を突き合わせる;

pub(super) fn 同じ種から同じバイト列が出ることを確かめる(
    種: マップ生成の乱数の種,
    広がり: 世界の広がり,
    親: 生成検収の親ディレクトリ,
) -> Result<(String, String), 場所巡りの通しの検収エラー> {
    let ソースの本数 = ソースの決定性を確かめる(種, 広がり, 親)?;
    let (実行時形式の本数, 遠景報告) = 実行時形式の決定性を確かめる(親)?;
    Ok((
        format!(
            "種{}からのクリーンな2つの生成が、ソース{ソースの本数}本と実行時形式{実行時形式の本数}本でバイト一致した",
            種.値()
        ),
        遠景報告,
    ))
}

fn ソースの決定性を確かめる(
    種: マップ生成の乱数の種,
    広がり: 世界の広がり,
    親: 生成検収の親ディレクトリ,
) -> Result<usize, 場所巡りの通しの検収エラー> {
    let 一度目 = 掃除してからソースを書き出す(種, 広がり, &検収用のルート::ソースの一度目(親))?;
    let 二度目 = 掃除してからソースを書き出す(種, 広がり, &検収用のルート::ソースの二度目(親))?;
    畳んだ値を突き合わせる(&一度目, &二度目, "ソース")
}

fn 実行時形式の決定性を確かめる(
    親: 生成検収の親ディレクトリ
) -> Result<(usize, String), 場所巡りの通しの検収エラー> {
    let ソースルート = 検収用のルート::ソースの一度目(親);
    let (一度目, 遠景報告) = 掃除してから実行時形式を焼く(&ソースルート, &検収用のルート::実行時形式の一度目(親))?;
    let (二度目, 二度目の報告) = 掃除してから実行時形式を焼く(&ソースルート, &検収用のルート::実行時形式の二度目(親))?;
    if 二度目の報告 != 遠景報告 {
        return Err(場所巡りの通しの検収エラー::遠景容量検収が失敗した(
            "2つのクリーン生成で遠景沈みの報告が一致しない".to_string(),
        ));
    }
    Ok((畳んだ値を突き合わせる(&一度目, &二度目, "実行時形式")?, 遠景報告))
}

fn 掃除してからソースを書き出す(
    種: マップ生成の乱数の種,
    広がり: 世界の広がり,
    ソースルート: &検収用のルート,
) -> Result<BTreeMap<PathBuf, u64>, 場所巡りの通しの検収エラー> {
    ソースルート.掃除する()?;
    ソースルート.既存素材を複写する()?;
    crate::gen_game_map::source_write::ソースルートと広がりを指定して書き出す(種, &ソースルート.ソースルートとして読む(), 広がり)
        .map_err(場所巡りの通しの検収エラー::ソースの生成が失敗した)?;
    ソースルート.場所巡りの生成物を畳む()
}

fn 掃除してから実行時形式を焼く(
    ソースルート: &検収用のルート,
    出力ルート: &検収用のルート,
) -> Result<(BTreeMap<PathBuf, u64>, String), 場所巡りの通しの検収エラー> {
    出力ルート.掃除する()?;
    let 標準出力 = crate::compile_assets::ルートを名指しして焼き標準出力を返す(
        ソースルート.プロセスへ渡すパス(),
        出力ルート.プロセスへ渡すパス(),
        crate::asset_generator::世界名::場所巡りの世界,
    )
    .map_err(場所巡りの通しの検収エラー::実行時形式の焼き付けが失敗した)?;
    let 遠景報告 = 標準出力
        .lines()
        .find(|行| 行.contains("遠景沈み"))
        .ok_or_else(|| 場所巡りの通しの検収エラー::遠景容量検収が失敗した("遠景沈みの報告行が無い".to_string()))?
        .to_string();
    Ok((出力ルート.全ファイルを畳む()?, 遠景報告))
}
