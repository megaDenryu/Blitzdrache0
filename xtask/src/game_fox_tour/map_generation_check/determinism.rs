//! 同じ種からの2つのクリーンな生成が同じバイト列になることを確かめる工程。受け取るのは種、返すのは突き合わせた本数の要約である。
//!
//! 突き合わせを2段に分けるのは、決定性が破れうる場所が2つあるためである。1つは種から高さを決める計算であり、
//! もう1つは高さ格子からメッシュと高さ場を焼く工程である。前者は2つの別のソースルートへの書き出しどうしを、
//! 後者は同じソースから2つの別の出力ルートへのコンパイルどうしを比べる。
//!
//! 実行時形式の側で2つのソースルートを使わないのは2つの事情による。1つは、実行時カタログがソースの依存一覧を
//! パスの綴りのまま持つため、ソースルートが違えばカタログのバイト列が当然違い、その差が決定性の破れではないこと。
//! もう1つは、この世界がキツネのglTFのように世界のディレクトリの外にあるソースも読み、そのソースは
//! 検収用のソースルートに無いことである。したがって実行時形式の突き合わせは既定のソースルートから焼く。
//!
//! 増分は各ルートを消してから走らせることで無効にする。増分の再実行との突き合わせにすると、焼き直していない
//! ファイルを自分自身と比べることになり空の検査になる。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

use std::collections::BTreeMap;
use std::path::PathBuf;

use super::check_root::検収用のルート;

pub(super) fn 同じ種から同じバイト列が出ることを確かめる(種: &str) -> Result<String, String> {
    let ソースの本数 = ソースの決定性を確かめる(種)?;
    let 実行時形式の本数 = 実行時形式の決定性を確かめる()?;
    Ok(format!(
        "種{種}からのクリーンな2つの生成が、ソース{ソースの本数}本と実行時形式{実行時形式の本数}本でバイト一致した"
    ))
}

fn ソースの決定性を確かめる(種: &str) -> Result<usize, String> {
    let 一度目 = 掃除してからソースを書き出す(種, &検収用のルート::ソースの一度目())?;
    let 二度目 = 掃除してからソースを書き出す(種, &検収用のルート::ソースの二度目())?;
    畳んだ値を突き合わせる(&一度目, &二度目, "ソース")
}

fn 実行時形式の決定性を確かめる() -> Result<usize, String> {
    let 一度目 = 掃除してから実行時形式を焼く(&検収用のルート::実行時形式の一度目())?;
    let 二度目 = 掃除してから実行時形式を焼く(&検収用のルート::実行時形式の二度目())?;
    畳んだ値を突き合わせる(&一度目, &二度目, "実行時形式")
}

fn 掃除してからソースを書き出す(種: &str, ソースルート: &検収用のルート) -> Result<BTreeMap<PathBuf, u64>, String> {
    ソースルート.掃除する()?;
    crate::gen_game_map::source_write::ソースルートを指定して書き出す(種, ソースルート.プロセスへ渡すパス())?;
    ソースルート.全ファイルを畳む()
}

fn 掃除してから実行時形式を焼く(出力ルート: &検収用のルート) -> Result<BTreeMap<PathBuf, u64>, String> {
    出力ルート.掃除する()?;
    crate::compile_assets::ルートを名指しして焼き標準出力を返す(
        crate::compile_assets::ソースルート(),
        出力ルート.プロセスへ渡すパス(),
        crate::compile_assets::場所巡りの世界,
    )?;
    出力ルート.全ファイルを畳む()
}

fn 畳んだ値を突き合わせる(
    一度目: &BTreeMap<PathBuf, u64>,
    二度目: &BTreeMap<PathBuf, u64>,
    何の突き合わせか: &str,
) -> Result<usize, String> {
    if 一度目.len() != 二度目.len() {
        return Err(format!(
            "{何の突き合わせか}の2つの生成でファイルの本数が食い違った({}本と{}本)",
            一度目.len(),
            二度目.len()
        ));
    }
    for (相対パス, 一度目の値) in 一度目 {
        let Some(二度目の値) = 二度目.get(相対パス) else {
            return Err(format!("{何の突き合わせか}の2つ目の生成に{}が無い", 相対パス.display()));
        };
        if 一度目の値 != 二度目の値 {
            return Err(format!("{何の突き合わせか}の2つの生成で{}の中身が食い違った", 相対パス.display()));
        }
    }
    Ok(一度目.len())
}
