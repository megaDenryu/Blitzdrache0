//! 生成器とコンパイラが報告する行から、焼き直したチャンクの本数を読む工程。受け取るのは取り込んだ標準出力、
//! 返すのは焼き直した本数である。
//!
//! 標準出力を終了時報告として受けるのは、報告の行を探して鍵に結ばれた数を読む手順が、アプリの報告を読む
//! 検収と同じだからである。読み手を2通り持つと、鍵の探し方が入口ごとに違って片方だけが静かに読めなくなる。
//!
//! 注意: 読み取る綴りは書き手(`crates/blitz_asset_compiler/src/generation_ledger/rebake_tally.rs`)にも同じものがある。
//! 食い違えば「報告の行が無い」で失敗する。黙って0本と読まないのは、増分が効いていないことを効いていると
//! 取り違えるほうが害が大きいためである。

#[cfg(test)]
mod tally_line_tests;

use crate::acceptance::{判定の名前, 検収の実行名, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

/// 本数の欄の綴り。等号まで含めて持つのは、生成器の行が鍵の直前に空白を置かないためである。
const 本数の欄の綴り: &str = "焼き直したチャンク数=";
const 本数の欄の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する(本数の欄の綴り);

/// 焼き直しの本数を報告する2つの生成器。行の見出しとその実行を指す名前をここが1つ持つ。
#[derive(Clone, Copy)]
pub(super) enum 焼き直しを報告する生成器 {
    ソースの生成器,
    アセットコンパイラ,
}

impl 焼き直しを報告する生成器 {
    fn 行の見出し(self) -> 報告の見出し {
        match self {
            Self::ソースの生成器 => 報告の見出し::定数から生成する("[generate_source_assets] "),
            Self::アセットコンパイラ => 報告の見出し::定数から生成する("[compile_assets] "),
        }
    }

    fn 実行名(self) -> 検収の実行名 {
        match self {
            Self::ソースの生成器 => 検収の実行名::定数から生成する("map_source_generation"),
            Self::アセットコンパイラ => 検収の実行名::定数から生成する("map_asset_compile"),
        }
    }

    fn 呼び名(self) -> &'static str {
        match self {
            Self::ソースの生成器 => "ソースの生成器",
            Self::アセットコンパイラ => "アセットコンパイラ",
        }
    }
}

/// 生成器が出す行のうち、本数の欄を持つ行から数を読む。生成器はほかにも自分の見出しで始まる行を出すため、
/// 見出しの最初の1行でなく本数の欄を持つ行を探す。
pub(super) fn 焼き直した本数を読む(
    標準出力: String, 生成器: 焼き直しを報告する生成器
) -> Result<usize, 検収エラー> {
    let 報告 = 終了時報告::取り込む(&生成器.実行名(), 標準出力, String::new());
    let 行一覧 = 報告.見出しで始まる行の一覧(&生成器.行の見出し());
    let 行 = 行一覧
        .iter()
        .find(|行| 行.原文().contains(本数の欄の綴り))
        .ok_or_else(|| 本数の欄の行の判定名(生成器).あるはずのものが無い破れ())?;
    行.鍵に結ばれた数(&本数の欄の鍵, 鍵に値が結ばれる形::この綴りに続く数字の並びが値である)
}

fn 本数の欄の行の判定名(生成器: 焼き直しを報告する生成器) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{}の報告の{本数の欄の綴り}を持つ行", 生成器.呼び名()))
}
