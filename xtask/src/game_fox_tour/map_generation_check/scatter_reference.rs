//! 散布を焼かない絵の対照を、候補と同じソースから焼く工程。受け取るのは種と広がり、返すのは要約である。
//!
//! 対照を「散布より前のコミットの作業ツリー」から採らないのは、比べている差へ散布以外のコミットの差が混ざり、
//! しかもその混ざりが絵から見分けられないためである。同じバイナリで焼き方の指定だけを分ければ、
//! 2枚の違いは散布だけになる。第5段階の検査点5が影の再配分で確立した規律をそのまま使う。
//!
//! ソースを自分で書き出すのは、決定性の検収が使い終えたソースを掃除するためである。同じ種と同じ広がりからは
//! 同じ高さ格子が出るため、候補のソースと1バイトも違わない。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`「第6段階」

use std::path::PathBuf;

use blitz_asset_compiler::{マップ生成の乱数の種, 世界の広がり, 散布の焼き方};

use super::super::error::場所巡りの通しの検収エラー;
use super::check_root::{検収用のルート, 生成検収の親ディレクトリ};

const 親: 生成検収の親ディレクトリ = 生成検収の親ディレクトリ::大規模世界;

pub(crate) fn 散布なしの対照を焼く(
    種: マップ生成の乱数の種,
    広がり: 世界の広がり,
) -> Result<String, 場所巡りの通しの検収エラー> {
    let ソース = 検収用のルート::散布対照のソース(親);
    let 実行時形式 = 検収用のルート::散布対照の実行時形式(親);
    ソース.既存素材を複写する()?;
    crate::gen_game_map::source_write::ソースルートと広がりを指定して書き出す(種, &ソース.ソースルートとして読む(), 広がり)
        .map_err(場所巡りの通しの検収エラー::ソースの生成が失敗した)?;
    crate::compile_assets::ルートを名指しして焼き標準出力を返す(
        ソース.プロセスへ渡すパス(),
        実行時形式.プロセスへ渡すパス(),
        crate::asset_generator::世界名::場所巡りの世界,
        親.遠景地形の焼き方(),
        散布の焼き方::焼かない,
    )
    .map_err(場所巡りの通しの検収エラー::実行時形式の焼き付けが失敗した)?;
    Ok(format!("散布を焼かない対照を{}へ焼いた", 実行時形式.プロセスへ渡すパス().display()))
}

pub(crate) fn 散布対照の実行時形式パス() -> PathBuf {
    検収用のルート::散布対照の実行時形式(親).プロセスへ渡すパス().to_path_buf()
}
