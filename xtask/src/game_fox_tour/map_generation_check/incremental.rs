//! 同じ種での再実行が1本も焼き直さないことを確かめる工程。受け取るのは種、返すのは確かめた内容の要約である。
//!
//! 増分が効いているという事実は生成物の中身に現れない。焼き直した本数が0本であることが唯一の証拠であるため、
//! 生成器とコンパイラが報告する本数をそのまま判定に使う。
//!
//! 既定のルートを対象にするのは、この検収の後に続く実行の段が同じルートを開くためである。1度目の実行で
//! 既定のルートを今の種の生成物へ揃え、2度目でその据え置きを確かめる。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

use super::super::error::場所巡りの通しの検収エラー;
use super::tally_line::{焼き直した本数を読む, 焼き直しを報告する生成器};
use crate::acceptance::判定の名前;

const ソースの焼き直し: 判定の名前 = 判定の名前::定数から生成する("同じ種での再実行がソースで焼き直したチャンク");
const 実行時形式の焼き直し: 判定の名前 = 判定の名前::定数から生成する("同じ種での再実行が実行時形式で焼き直したチャンク");

pub(super) fn 同じ種での再実行が焼き直さないことを確かめる(
    種: &str,
) -> Result<String, 場所巡りの通しの検収エラー> {
    既定のルートへ一度生成する(種)?;
    let ソースの出力 = 既定のソースルートへ書き出す(種)?;
    let ソースの本数 = 焼き直した本数を読む(ソースの出力, 焼き直しを報告する生成器::ソースの生成器)?;
    let コンパイルの出力 = 既定の出力ルートへ焼く()?;
    let コンパイルの本数 = 焼き直した本数を読む(コンパイルの出力, 焼き直しを報告する生成器::アセットコンパイラ)?;
    ソースの焼き直し.零件であることを課す(ソースの本数)?;
    実行時形式の焼き直し.零件であることを課す(コンパイルの本数)?;
    Ok(format!("種{種}での再実行が焼き直したチャンクは0本だった"))
}

fn 既定のルートへ一度生成する(種: &str) -> Result<(), 場所巡りの通しの検収エラー> {
    既定のソースルートへ書き出す(種)?;
    既定の出力ルートへ焼く().map(|_| ())
}

fn 既定のソースルートへ書き出す(種: &str) -> Result<String, 場所巡りの通しの検収エラー> {
    crate::gen_game_map::source_write::既定のソースルートへ書き出す(種)
        .map_err(|理由| 場所巡りの通しの検収エラー::ソースの生成が失敗した { 理由 })
}

fn 既定の出力ルートへ焼く() -> Result<String, 場所巡りの通しの検収エラー> {
    crate::compile_assets::ルートを名指しして焼き標準出力を返す(
        crate::compile_assets::ソースルート(),
        crate::compile_assets::場所巡りの既定出力ルートのパス(),
        crate::asset_generator::世界名::場所巡りの世界,
    )
    .map_err(|理由| 場所巡りの通しの検収エラー::実行時形式の焼き付けが失敗した { 理由 })
}
