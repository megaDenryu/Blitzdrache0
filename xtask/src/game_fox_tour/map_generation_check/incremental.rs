//! 検収専用ルートで、同じ種の再実行が1本も焼き直さないことを確かめる。

use blitz_asset_compiler::マップ生成の乱数の種;

use super::super::error::場所巡りの通しの検収エラー;
use super::check_root::検収用のルート;
use super::tally_line::{焼き直した本数を読む, 焼き直しを報告する生成器};
use crate::acceptance::判定の名前;

const ソースの焼き直し: 判定の名前 = 判定の名前::定数から生成する("同じ種での再実行がソースで焼き直したチャンク");
const 実行時形式の焼き直し: 判定の名前 = 判定の名前::定数から生成する("同じ種での再実行が実行時形式で焼き直したチャンク");

pub(super) fn 同じ種での再実行が焼き直さないことを確かめる(
    種: マップ生成の乱数の種,
) -> Result<String, 場所巡りの通しの検収エラー> {
    let ソース = 検収用のルート::増分のソース();
    let 実行時形式 = 検収用のルート::増分の実行時形式();
    ソース.掃除する()?;
    実行時形式.掃除する()?;
    ソース.既存素材を複写する()?;
    一度生成する(種, &ソース, &実行時形式)?;
    let ソースの出力 = ソースを書き出す(種, &ソース)?;
    let コンパイルの出力 = 実行時形式を焼く(&ソース, &実行時形式)?;
    let ソースの本数 = 焼き直した本数を読む(ソースの出力, 焼き直しを報告する生成器::ソースの生成器)?;
    let コンパイルの本数 = 焼き直した本数を読む(コンパイルの出力, 焼き直しを報告する生成器::アセットコンパイラ)?;
    ソースの焼き直し.零件であることを課す(ソースの本数)?;
    実行時形式の焼き直し.零件であることを課す(コンパイルの本数)?;
    Ok(format!("種{}での再実行が焼き直したチャンクは0本だった", 種.値()))
}

fn 一度生成する(
    種: マップ生成の乱数の種,
    ソース: &検収用のルート,
    実行時形式: &検収用のルート,
) -> Result<(), 場所巡りの通しの検収エラー> {
    ソースを書き出す(種, ソース)?;
    実行時形式を焼く(ソース, 実行時形式).map(|_| ())
}

fn ソースを書き出す(
    種: マップ生成の乱数の種, ソース: &検収用のルート
) -> Result<String, 場所巡りの通しの検収エラー> {
    crate::gen_game_map::source_write::ソースルートを指定して書き出す(種, &ソース.ソースルートとして読む())
        .map_err(場所巡りの通しの検収エラー::ソースの生成が失敗した)
}

fn 実行時形式を焼く(
    ソース: &検収用のルート, 実行時形式: &検収用のルート
) -> Result<String, 場所巡りの通しの検収エラー> {
    crate::compile_assets::ルートを名指しして焼き標準出力を返す(
        ソース.プロセスへ渡すパス(),
        実行時形式.プロセスへ渡すパス(),
        crate::asset_generator::世界名::場所巡りの世界,
    )
    .map_err(場所巡りの通しの検収エラー::実行時形式の焼き付けが失敗した)
}
