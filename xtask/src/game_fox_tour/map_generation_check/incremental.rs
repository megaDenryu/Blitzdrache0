//! 同じ種での再実行が1本も焼き直さないことを確かめる工程。受け取るのは種、返すのは確かめた内容の要約である。
//!
//! 増分が効いているという事実は生成物の中身に現れない。焼き直した本数が0本であることが唯一の証拠であるため、
//! 生成器とコンパイラが報告する本数をそのまま判定に使う。
//!
//! 既定のルートを対象にするのは、この検収の後に続く実行の段が同じルートを開くためである。1度目の実行で
//! 既定のルートを今の種の生成物へ揃え、2度目でその据え置きを確かめる。
//! 参照: `_doc/設計/大規模世界の生成と遠景.md`

use super::tally_line::焼き直した本数を読む;

pub(super) fn 同じ種での再実行が焼き直さないことを確かめる(種: &str) -> Result<String, String> {
    既定のルートへ一度生成する(種)?;
    let ソースの出力 = crate::gen_game_map::source_write::既定のソースルートへ書き出す(種)?;
    let ソースの本数 = 焼き直した本数を読む(&ソースの出力, "ソースの生成器")?;
    let コンパイルの出力 = 既定の出力ルートへ焼く()?;
    let コンパイルの本数 = 焼き直した本数を読む(&コンパイルの出力, "アセットコンパイラ")?;
    if ソースの本数 != 0 || コンパイルの本数 != 0 {
        return Err(format!(
            "同じ種での再実行が焼き直した(ソース{ソースの本数}本、実行時形式{コンパイルの本数}本。どちらも0本であるべきである)"
        ));
    }
    Ok(format!("種{種}での再実行が焼き直したチャンクは0本だった"))
}

fn 既定のルートへ一度生成する(種: &str) -> Result<(), String> {
    crate::gen_game_map::source_write::既定のソースルートへ書き出す(種)?;
    既定の出力ルートへ焼く().map(|_| ())
}

fn 既定の出力ルートへ焼く() -> Result<String, String> {
    crate::compile_assets::ルートを名指しして焼き標準出力を返す(
        crate::compile_assets::ソースルート(),
        crate::compile_assets::場所巡りの既定出力ルートのパス(),
        crate::compile_assets::場所巡りの世界,
    )
}
