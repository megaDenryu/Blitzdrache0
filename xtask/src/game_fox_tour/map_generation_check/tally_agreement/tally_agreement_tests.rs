//! 2つの個体数の突き合わせを反証可能な形で固定する。見るのは、群の描画対象への載せ漏れを模した報告が落ちることと、
//! 一致する報告が通ることと、据え置いたチャンクがある実行では一致を課さないことと、種類ごとの内訳の行を
//! 落とした報告が落ちることの4つである。
//!
//! 載せ漏れを模すのは、焼く工程が置いた側だけが多い報告を組み立てることである。配置は作られたのに群がシーンへ
//! 載らなかった実行の報告はこの形になる。実際に載せ漏れる生成物を作るには工程を壊すしかないため、
//! 網が張れているかは報告の形で反証する。

#![allow(clippy::unwrap_used)]

use super::super::compile_report::コンパイルの報告;
use super::焼く工程とカタログの個体数が一致することを確かめる;

fn 報告を組み立てる(焼き直した: usize, 据え置いた: usize, 置いた: usize, カタログ: usize) -> コンパイルの報告 {
    let 標準出力 = format!(
        "[compile_assets] 焼き直したチャンク数={焼き直した} 据え置いたチャンク数={据え置いた}\n\
         [compile_assets] 置いた個体の合計={置いた}\n\
         [compile_assets] 種類ごとの置いた個体: 樫の木={置いた}\n\
         [compile_assets] 個体数の合計={カタログ} 個体を持つ対象数=2\n"
    );
    コンパイルの報告::標準出力から読む(標準出力)
}

/// 種類ごとの内訳の行を落とした報告。焼く工程はこの行を必ず出すため、無い報告は報告の側の欠落である。
fn 内訳の行を持たない報告() -> コンパイルの報告 {
    let 標準出力 = "[compile_assets] 焼き直したチャンク数=9 据え置いたチャンク数=0\n\
                    [compile_assets] 置いた個体の合計=480\n\
                    [compile_assets] 個体数の合計=480 個体を持つ対象数=2\n"
        .to_string();
    コンパイルの報告::標準出力から読む(標準出力)
}

#[test]
fn 群の描画対象への載せ漏れを模した報告は落ちる() {
    let 結果 = 焼く工程とカタログの個体数が一致することを確かめる(&報告を組み立てる(9, 0, 480, 320));
    assert!(結果.is_err(), "置いた側だけが多い報告を通した");
}

#[test]
fn 個体数が一致する報告は通る() {
    let 要約 = 焼く工程とカタログの個体数が一致することを確かめる(&報告を組み立てる(9, 0, 480, 480)).unwrap();
    assert!(要約.contains("480"), "要約が突き合わせた数を名指していない: {要約}");
}

/// 据え置いた対象は焼く工程を通らず置いた個体を1体も数えないため、増分が効いた実行では2つの数が正当に食い違う。
#[test]
fn 据え置いたチャンクがある実行では一致を課さない() {
    let 要約 = 焼く工程とカタログの個体数が一致することを確かめる(&報告を組み立てる(0, 9, 0, 480)).unwrap();
    assert!(要約.contains("課さない"), "据え置きのある実行で一致を課した: {要約}");
}

/// **合計だけでは木と岩の取り分が分からない。** 行が出なくなったことを検収が黙って見過ごすと、
/// 内訳を読む側が「散らした種類が1つも無かった」と読み違える。
#[test]
fn 内訳の行が無い報告は落ちる() {
    let 結果 = 焼く工程とカタログの個体数が一致することを確かめる(&内訳の行を持たない報告());
    assert!(結果.is_err(), "内訳の行が無い報告を通した");
}

/// 通った実行の要約は内訳をそのまま持ち越す。人が読む診断であるため、数の突き合わせでなく綴りの持ち越しを見る。
#[test]
fn 要約は種類ごとの内訳を持ち越す() {
    let 要約 = 焼く工程とカタログの個体数が一致することを確かめる(&報告を組み立てる(9, 0, 480, 480)).unwrap();
    assert!(要約.contains("樫の木=480"), "要約が内訳を持ち越していない: {要約}");
}
