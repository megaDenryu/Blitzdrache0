//! 焼き直した本数の読み取りを反証可能な形で固定する。見るのは、報告の行から本数を読めることと、
//! 行が無い報告を黙って0本と読まないことである。

#![allow(clippy::unwrap_used)]

use super::{焼き直した本数を読む, 焼き直しを報告する生成器};

#[test]
fn 報告の行から本数を読む() {
    let 出力 = "[compile_assets] 焼いた\n[compile_assets] 焼き直したチャンク数=3 据え置いたチャンク数=6\n";
    let 本数 = 焼き直した本数を読む(出力.to_string(), 焼き直しを報告する生成器::アセットコンパイラ).unwrap();
    assert_eq!(本数, 3);
}

/// 生成器の行は鍵の直前に空白を置かない。空白で切った語の頭では鍵を見つけられないことをこれが固定する。
#[test]
fn 空白の無い生成器の行からも本数を読む() {
    let 出力 = "[generate_source_assets] assets/fox_tour_worldへ種20260810から生成完了、焼き直したチャンク数=0 据え置いたチャンク数=9\n";
    let 本数 = 焼き直した本数を読む(出力.to_string(), 焼き直しを報告する生成器::ソースの生成器).unwrap();
    assert_eq!(本数, 0);
}

#[test]
fn 報告の行が無ければ失敗する() {
    let 結果 = 焼き直した本数を読む("[compile_assets] 焼いた\n".to_string(), 焼き直しを報告する生成器::アセットコンパイラ);
    assert!(結果.is_err());
}
