//! 場所巡りの通しの検収が返す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。
//! 様式は`acceptance/error.rs`と`depth_prepass_cost/error.rs`に倣う。
//!
//! 検収の器の破れと判定の破れを枝で内包するのは、この入口が地図の生成と起動と判定を一続きに通すためである。
//! 3つを別の型で返すと、通す側が段ごとに変換を書くことになる。
//!
//! 生成器の起動とファイルの走査をここが持つのは、どちらも判定でも報告の読み取りでもないためである。
//! 生成器の破れを2つの枝で持つのは、同じ生成器の失敗でも、ソースを書き出す段と実行時形式へ焼く段では
//! 直す側が見る場所が違うためである。人が読む1文へ写すのは`display`が持つ。

mod display;

use std::path::PathBuf;

use crate::acceptance::{判定の破れ, 検収エラー};
use crate::asset_generator::生成器エラー;

#[derive(Debug)]
pub(super) enum 場所巡りの通しの検収エラー {
    検収の器が破れた(検収エラー),
    判定が破れた(判定の破れ),
    ソースの生成が失敗した(生成器エラー),
    実行時形式の焼き付けが失敗した(生成器エラー),
    検収用のルートを消せなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    ディレクトリを開けなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    ディレクトリの走査に失敗した {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    /// ルートの下にあるはずのパスがルートから始まっていない。到達すれば走査の起点が食い違っている。
    相対パスを求められなかった {
        パス: PathBuf,
    },
    ファイルを開けなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    ファイルを読めなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
}

impl std::error::Error for 場所巡りの通しの検収エラー {}

impl From<検収エラー> for 場所巡りの通しの検収エラー {
    fn from(破れ: 検収エラー) -> Self {
        Self::検収の器が破れた(破れ)
    }
}

impl From<判定の破れ> for 場所巡りの通しの検収エラー {
    fn from(破れ: 判定の破れ) -> Self {
        Self::判定が破れた(破れ)
    }
}
