//! 検収1条件ぶんの起動の指定と、その実行が報告した進行の取り込み。受け取るのは実行環境と実行名と条件、
//! 返すのは報告から読み取った進行の値である。起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! 世界を開く指定は遊ぶ入口と共有する(`fox_tour_launch`)。検収が通った条件と遊ぶ条件を別物にしないためである。
//! フレーム数を条件ごとに変えるのは、台本が段階を更新の回数で区切っており、見たい段階のフレームで絵を撮るためである。

use crate::acceptance::{アプリの起動指定, 描画フレーム数, 描画検収の実行環境, 検収の実行名};

/// その実行のゲームの操作をどこから採るか。
#[derive(Clone, Copy)]
pub(super) enum 操作の出どころ {
    /// 決定的な台本。段階を更新の回数で区切って進める。
    決定的な台本,
    /// 実行時の入力。フレーム数の決まった実行では適用方針が1つも通さないため、キツネはタイトル表示中のまま動かない。
    実行時の入力,
}

/// その実行が報告したゲームの進行。
pub(super) struct 実行の進行 {
    pub(super) ゲーム更新の回数: String,
    pub(super) 最後の進行段階: String,
    pub(super) 到達済みの目的地: String,
    pub(super) プレイヤーの大域位置: String,
}

pub(super) fn 描画する(
    実行環境: &描画検収の実行環境,
    実行名の綴り: &str,
    フレーム数: 描画フレーム数,
    出どころ: 操作の出どころ,
) -> Result<実行の進行, String> {
    let 実行 = 実行環境.描いて読み戻す(検収の実行名::生成する(実行名の綴り)?, &起動指定を組み立てる(フレーム数, 出どころ))?;
    進行を読み取る(実行名の綴り, 実行.報告().本文())
}

fn 起動指定を組み立てる(フレーム数: 描画フレーム数, 出どころ: 操作の出どころ) -> アプリの起動指定 {
    crate::fox_tour_launch::枚数を決めて世界を開く(フレーム数).値を持つ選択肢を足す("--game", ゲームの引数値(出どころ))
}

fn ゲームの引数値(出どころ: 操作の出どころ) -> &'static str {
    match 出どころ {
        操作の出どころ::決定的な台本 => "fox_tour_scripted",
        操作の出どころ::実行時の入力 => "fox_tour",
    }
}

fn 進行を読み取る(実行名の綴り: &str, 標準出力: &str) -> Result<実行の進行, String> {
    Ok(実行の進行 {
        ゲーム更新の回数: 行の値を読む(標準出力, "  ゲーム更新の回数: ", 実行名の綴り)?,
        最後の進行段階: 行の値を読む(標準出力, "  最後の進行段階: ", 実行名の綴り)?,
        到達済みの目的地: 行の値を読む(標準出力, "  到達済みの目的地: ", 実行名の綴り)?,
        プレイヤーの大域位置: 行の値を読む(標準出力, "  プレイヤーの大域位置: ", 実行名の綴り)?,
    })
}

/// 見出しで始まる行の値。ゲームの進行の報告が出ていない実行は、ゲーム更新が1度も走っていないため失敗として扱う。
fn 行の値を読む(標準出力: &str, 見出し: &str, 実行名の綴り: &str) -> Result<String, String> {
    標準出力
        .lines()
        .find_map(|行| 行.strip_prefix(見出し))
        .map(str::trim)
        .map(str::to_string)
        .ok_or_else(|| format!("{実行名の綴り}の出力に「{}」の行が無い", 見出し.trim()))
}
