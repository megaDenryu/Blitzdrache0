//! 検収1条件ぶんの起動の指定と、その実行が報告した進行の取り込み。受け取るのは実行環境と実行名と条件、
//! 返すのは報告から読み取った進行の値である。起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! 世界を開く指定は遊ぶ入口と共有する(`fox_tour_launch`)。検収が通った条件と遊ぶ条件を別物にしないためである。
//! フレーム数を条件ごとに変えるのは、台本が段階を更新の回数で区切っており、見たい段階のフレームで絵を撮るためである。
//!
//! 注意: 書き出させるだけで読み戻さない。終了までの条件は台本が251回目の更新で終了を決め、最終フレームへ着く前に
//! イベントループが閉じるため、書き出しが1つも残らない。ここで読み戻すと、その条件だけが「絵が無い」で落ちる。
//! 絵を要る判定(2回の実行のバイト一致)と目視材料の変換は、撮り終えた後に置き場から名前で読む。

use crate::acceptance::{
    アプリの起動指定, 描画フレーム数, 描画検収の実行環境, 書き出しの形式, 検収の実行名, 検収エラー, 終了時報告
};
use crate::report_heading::報告の見出し;

/// その実行のゲームの操作をどこから採るか。
#[derive(Clone, Copy)]
pub(super) enum 操作の出どころ {
    /// 決定的な台本。段階を更新の回数で区切って進める。
    決定的な台本,
    /// 実行時の入力。フレーム数の決まった実行では適用方針が1つも通さないため、キツネはタイトル表示中のまま動かない。
    実行時の入力,
}

/// その実行が報告したゲームの進行。
pub(super) struct 実行の進行 {
    pub(super) ゲーム更新の回数: String,
    pub(super) 最後の進行段階: String,
    pub(super) 到達済みの目的地: String,
    pub(super) プレイヤーの大域位置: String,
}

const ゲーム更新の回数の見出し: 報告の見出し = 報告の見出し::定数から生成する("ゲーム更新の回数:");
const 最後の進行段階の見出し: 報告の見出し = 報告の見出し::定数から生成する("最後の進行段階:");
const 到達済みの目的地の見出し: 報告の見出し = 報告の見出し::定数から生成する("到達済みの目的地:");
const プレイヤーの大域位置の見出し: 報告の見出し = 報告の見出し::定数から生成する("プレイヤーの大域位置:");

pub(super) fn 描画する(
    実行環境: &描画検収の実行環境,
    実行名の綴り: &str,
    フレーム数: 描画フレーム数,
    出どころ: 操作の出どころ,
) -> Result<実行の進行, 検収エラー> {
    let 報告 = 実行環境.書き出させて報告を採る(
        検収の実行名::生成する(実行名の綴り)?,
        &起動指定を組み立てる(フレーム数, 出どころ),
        書き出しの形式::提示画像,
    )?;
    進行を読み取る(&報告)
}

fn 起動指定を組み立てる(フレーム数: 描画フレーム数, 出どころ: 操作の出どころ) -> アプリの起動指定 {
    crate::fox_tour_launch::枚数を決めて世界を開く(フレーム数).値を持つ選択肢を足す("--game", ゲームの引数値(出どころ))
}

fn ゲームの引数値(出どころ: 操作の出どころ) -> &'static str {
    match 出どころ {
        操作の出どころ::決定的な台本 => "fox_tour_scripted",
        操作の出どころ::実行時の入力 => "fox_tour",
    }
}

/// 見出しに続く本文をそのまま採るのは、到達済みの目的地と大域位置が空白を含む1つの値だからである。
/// ゲームの進行の報告が出ていない実行は、ゲーム更新が1度も走っていないため失敗として扱う。
fn 進行を読み取る(報告: &終了時報告) -> Result<実行の進行, 検収エラー> {
    Ok(実行の進行 {
        ゲーム更新の回数: 報告.見出しに続く本文(&ゲーム更新の回数の見出し)?.to_string(),
        最後の進行段階: 報告.見出しに続く本文(&最後の進行段階の見出し)?.to_string(),
        到達済みの目的地: 報告.見出しに続く本文(&到達済みの目的地の見出し)?.to_string(),
        プレイヤーの大域位置: 報告.見出しに続く本文(&プレイヤーの大域位置の見出し)?.to_string(),
    })
}
