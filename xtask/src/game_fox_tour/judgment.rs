//! 実機の実行の結果を機械で判定する工程。受け取るのは実行の進行と書き出したバイト列、返すのは合格の要約である。
//! 判定は5つの破れ方を弾く。台本が1つも目的地へ着かない、台本が終了まで進まない、同じ引数の2回で進行が食い違う、
//! 同じ引数の2回で絵が食い違う、フレーム数の決まった実行が実ウィンドウの操作を通してキツネを動かす、の5つである。

use super::run::実行の進行;
use crate::acceptance::{描画検収の実行環境, 検収の実行名};

/// 目的地へ着いた実行が報告する到達の綴り。道順は3つであり、1つ目へ着いた時点でこの綴りになる。
const 一つ目へ着いた綴り: &str = "1 / 3";
/// 1つも巡っていない実行が報告する到達の綴り。
const 一つも巡っていない綴り: &str = "0 / 3";
const タイトル表示中の呼び名: &str = "タイトル表示中";
const 終了決定済みの呼び名: &str = "終了決定済み";

pub(super) fn 台本が目的地へ着くことを確かめる(進行: &実行の進行) -> Result<(), String> {
    if 進行.到達済みの目的地 == 一つ目へ着いた綴り {
        return Ok(());
    }
    Err(format!(
        "台本の操作で1つ目の目的地へ着かなかった(到達済み{}、位置{})",
        進行.到達済みの目的地, 進行.プレイヤーの大域位置
    ))
}

pub(super) fn 台本が終了まで進むことを確かめる(進行: &実行の進行) -> Result<(), String> {
    if 進行.最後の進行段階 == 終了決定済みの呼び名 && 進行.到達済みの目的地 == 一つ目へ着いた綴り {
        return Ok(());
    }
    Err(format!(
        "台本の操作が終了の決定まで進まなかった(段階{}、到達済み{})",
        進行.最後の進行段階, 進行.到達済みの目的地
    ))
}

pub(super) fn 二回の実行が同じ進行で終わることを確かめる(
    一回目: &実行の進行, 二回目: &実行の進行
) -> Result<String, String> {
    項目を突き合わせる("ゲーム更新の回数", &一回目.ゲーム更新の回数, &二回目.ゲーム更新の回数)?;
    項目を突き合わせる("最後の進行段階", &一回目.最後の進行段階, &二回目.最後の進行段階)?;
    項目を突き合わせる("到達済みの目的地", &一回目.到達済みの目的地, &二回目.到達済みの目的地)?;
    項目を突き合わせる("プレイヤーの大域位置", &一回目.プレイヤーの大域位置, &二回目.プレイヤーの大域位置)?;
    Ok(format!(
        "2回の実行が同じ進行で終わった(更新{}回、段階{}、到達済み{}、位置{})",
        一回目.ゲーム更新の回数, 一回目.最後の進行段階, 一回目.到達済みの目的地, 一回目.プレイヤーの大域位置
    ))
}

/// フレーム数の決まった実行が実ウィンドウの操作を1つも通さないことの反証。通してしまうと、絵の判定を持つ既存の
/// 入口が実行のたびに違う絵を返す。台本の実行と位置が同じでないことも併せて見る。
pub(super) fn 台本なしの実行がタイトルのまま終わることを確かめる(
    台本なし: &実行の進行,
    台本あり: &実行の進行,
) -> Result<(), String> {
    if 台本なし.最後の進行段階 != タイトル表示中の呼び名 || 台本なし.到達済みの目的地 != 一つも巡っていない綴り
    {
        return Err(format!(
            "フレーム数の決まった実行が実ウィンドウの操作でゲームを進めた(段階{}、到達済み{})",
            台本なし.最後の進行段階, 台本なし.到達済みの目的地
        ));
    }
    if 台本なし.プレイヤーの大域位置 == 台本あり.プレイヤーの大域位置 {
        return Err("台本の操作でキツネが出発地点から1歩も動かなかった".to_string());
    }
    Ok(())
}

pub(super) fn 二回の実行の絵がバイト一致することを確かめる(
    実行環境: &描画検収の実行環境,
    一回目の出力名: &str,
    二回目の出力名: &str,
) -> Result<(), String> {
    let 一回目 = 実行環境.同じ置き場の書き出しを読み戻す(検収の実行名::生成する(一回目の出力名)?)?;
    let 二回目 = 実行環境.同じ置き場の書き出しを読み戻す(検収の実行名::生成する(二回目の出力名)?)?;
    if 一回目.バイト列() == 二回目.バイト列() {
        return Ok(());
    }
    Err("同じ引数の2回の実行が違う絵を返した".to_string())
}

fn 項目を突き合わせる(項目: &str, 一回目: &str, 二回目: &str) -> Result<(), String> {
    if 一回目 == 二回目 {
        return Ok(());
    }
    Err(format!("2回の実行で{項目}が食い違った({一回目} と {二回目})"))
}
