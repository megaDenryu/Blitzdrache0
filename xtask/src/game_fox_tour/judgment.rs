//! 実機の実行の結果を機械で判定する工程。受け取るのは実行の進行と書き出したバイト列、返すのは合格の要約である。
//! 判定は5つの破れ方を弾く。台本が1つも目的地へ着かない、台本が終了まで進まない、同じ引数の2回で進行が食い違う、
//! 同じ引数の2回で絵が食い違う、フレーム数の決まった実行が実ウィンドウの操作を通してキツネを動かす、の5つである。

use super::run::実行の進行;
use crate::acceptance::{判定の名前, 判定の破れ, 描画検収の実行環境, 検収の実行名, 検収エラー};

/// 目的地へ着いた実行が報告する到達の綴り。道順は3つであり、1つ目へ着いた時点でこの綴りになる。
const 一つ目へ着いた綴り: &str = "1 / 3";
/// 1つも巡っていない実行が報告する到達の綴り。
const 一つも巡っていない綴り: &str = "0 / 3";
const タイトル表示中の呼び名: &str = "タイトル表示中";
const 終了決定済みの呼び名: &str = "終了決定済み";

const 台本なしの実行の段階: 判定の名前 =
    判定の名前::定数から生成する("台本なしの実行の最後の進行段階(進んだのは実ウィンドウの操作が通ったからである)");
const 台本なしの実行の到達: 判定の名前 =
    判定の名前::定数から生成する("台本なしの実行の到達済みの目的地(進んだのは実ウィンドウの操作が通ったからである)");
const 二回の実行の絵: 判定の名前 = 判定の名前::定数から生成する("同じ引数の2回の実行の絵がバイト一致すること");

pub(super) fn 台本が目的地へ着くことを確かめる(進行: &実行の進行) -> Result<(), 判定の破れ> {
    判定名を組む(&format!("台本の操作で着いた目的地(位置{})", 進行.プレイヤーの大域位置))
        .綴りの一致を課す(&進行.到達済みの目的地, 一つ目へ着いた綴り)
}

pub(super) fn 台本が終了まで進むことを確かめる(進行: &実行の進行) -> Result<(), 判定の破れ> {
    判定名を組む("台本の操作が終了の決定まで進んだときの最後の進行段階").綴りの一致を課す(&進行.最後の進行段階, 終了決定済みの呼び名)?;
    判定名を組む("台本の操作が終了の決定まで進んだときの到達済みの目的地").綴りの一致を課す(&進行.到達済みの目的地, 一つ目へ着いた綴り)
}

pub(super) fn 二回の実行が同じ進行で終わることを確かめる(
    一回目: &実行の進行,
    二回目: &実行の進行,
) -> Result<String, 判定の破れ> {
    項目を突き合わせる("ゲーム更新の回数", &一回目.ゲーム更新の回数, &二回目.ゲーム更新の回数)?;
    項目を突き合わせる("最後の進行段階", &一回目.最後の進行段階, &二回目.最後の進行段階)?;
    項目を突き合わせる("到達済みの目的地", &一回目.到達済みの目的地, &二回目.到達済みの目的地)?;
    項目を突き合わせる("プレイヤーの大域位置", &一回目.プレイヤーの大域位置, &二回目.プレイヤーの大域位置)?;
    Ok(format!(
        "2回の実行が同じ進行で終わった(更新{}回、段階{}、到達済み{}、位置{})",
        一回目.ゲーム更新の回数, 一回目.最後の進行段階, 一回目.到達済みの目的地, 一回目.プレイヤーの大域位置
    ))
}

/// フレーム数の決まった実行が実ウィンドウの操作を1つも通さないことの反証。通してしまうと、絵の判定を持つ既存の
/// 入口が実行のたびに違う絵を返す。台本の実行と位置が同じでないことも併せて見る。
pub(super) fn 台本なしの実行がタイトルのまま終わることを確かめる(
    台本なし: &実行の進行,
    台本あり: &実行の進行,
) -> Result<(), 判定の破れ> {
    台本なしの実行の段階.綴りの一致を課す(&台本なし.最後の進行段階, タイトル表示中の呼び名)?;
    台本なしの実行の到達.綴りの一致を課す(&台本なし.到達済みの目的地, 一つも巡っていない綴り)?;
    キツネが動いたことの判定名(&台本あり.プレイヤーの大域位置)
        .真であることを課す(台本なし.プレイヤーの大域位置 != 台本あり.プレイヤーの大域位置)
}

pub(super) fn 二回の実行の絵がバイト一致することを確かめる(
    実行環境: &描画検収の実行環境,
    一回目の出力名: &str,
    二回目の出力名: &str,
) -> Result<(), 検収エラー> {
    let 一回目 = 実行環境.同じ置き場の書き出しを読み戻す(検収の実行名::生成する(一回目の出力名)?)?;
    let 二回目 = 実行環境.同じ置き場の書き出しを読み戻す(検収の実行名::生成する(二回目の出力名)?)?;
    Ok(二回の実行の絵.真であることを課す(一回目.バイト列() == 二回目.バイト列())?)
}

fn 項目を突き合わせる(項目: &str, 一回目: &str, 二回目: &str) -> Result<(), 判定の破れ> {
    判定名を組む(&format!("2回の実行の{項目}")).綴りの一致を課す(二回目, 一回目)
}

/// 台本ありの位置を綴りへ入れるのは、真偽で課す判定が比べた綴りを文面へ出せないためである。
fn キツネが動いたことの判定名(台本ありの位置: &str) -> 判定の名前 {
    判定名を組む(&format!("台本の操作でキツネが出発地点から動いたこと(台本ありの位置{台本ありの位置})"))
}

fn 判定名を組む(綴り: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(綴り.to_string())
}
