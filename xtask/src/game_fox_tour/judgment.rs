//! 実機の実行の結果を機械で判定する工程。受け取るのは実行の進行と書き出したバイト列、返すのは合格の要約である。
//! 判定は3つの破れ方を弾く。2回の実行の進行が食い違う、2回の実行の絵が食い違う、台本の操作でキツネが1歩も動かない、の3つである。

use std::path::Path;

use super::run::実行の進行;

/// 出発地点にいるとみなす大域位置の綴り。報告は小数第6位まで出すため、動いていない実行はこの1つの綴りになる。
const 出発地点の綴り: &str = "東0.000000 天頂0.000000 南0.000000";

pub(super) fn 二回の実行が同じ進行で終わることを確かめる(
    一回目: &実行の進行, 二回目: &実行の進行
) -> Result<String, String> {
    項目を突き合わせる("ゲーム更新の回数", &一回目.ゲーム更新の回数, &二回目.ゲーム更新の回数)?;
    項目を突き合わせる("最後の進行段階", &一回目.最後の進行段階, &二回目.最後の進行段階)?;
    項目を突き合わせる("プレイヤーの大域位置", &一回目.プレイヤーの大域位置, &二回目.プレイヤーの大域位置)?;
    if 一回目.プレイヤーの大域位置 == 出発地点の綴り {
        return Err("台本の操作でキツネが出発地点から1歩も動かなかった".to_string());
    }
    Ok(format!(
        "2回の実行が同じ進行で終わった(更新{}回、段階{}、位置{})",
        一回目.ゲーム更新の回数, 一回目.最後の進行段階, 一回目.プレイヤーの大域位置
    ))
}

pub(super) fn 台本なしの実行が出発地点のまま終わることを確かめる(進行: &実行の進行) -> Result<(), String> {
    if 進行.プレイヤーの大域位置 == 出発地点の綴り {
        return Ok(());
    }
    Err(format!(
        "フレーム数の決まった実行が実ウィンドウの操作を通してキツネを動かした(位置{})",
        進行.プレイヤーの大域位置
    ))
}

pub(super) fn 二回の実行の絵がバイト一致することを確かめる(
    出力先: &Path,
    一回目の出力名: &str,
    二回目の出力名: &str,
) -> Result<(), String> {
    let 一回目 = 読み戻しを読む(出力先, 一回目の出力名)?;
    let 二回目 = 読み戻しを読む(出力先, 二回目の出力名)?;
    if 一回目 == 二回目 {
        return Ok(());
    }
    Err("同じ引数の2回の実行が違う絵を返した".to_string())
}

fn 読み戻しを読む(出力先: &Path, 出力名: &str) -> Result<Vec<u8>, String> {
    let パス = 出力先.join(出力名).with_extension("raw");
    std::fs::read(&パス).map_err(|誤り| format!("{}を読めなかった: {誤り}", パス.display()))
}

fn 項目を突き合わせる(項目: &str, 一回目: &str, 二回目: &str) -> Result<(), String> {
    if 一回目 == 二回目 {
        return Ok(());
    }
    Err(format!("2回の実行で{項目}が食い違った({一回目} と {二回目})"))
}
