//! 検収がどの段階をどのフレーム数で撮るかの台帳。担当するのは条件の一覧を1箇所へ持つことだけであり、
//! 起動も判定もここは行わない。
//!
//! フレーム数は台本の区切り(`crates/blitz_app/src/game/scripted_operation.rs`)に合わせてある。
//! 撮る条件を段階ごとに分けるのは、フレームの書き出しが`--frames`の最終フレームでだけ起きるためである。

use crate::acceptance::描画フレーム数;

/// 1条件ぶんの撮影。
pub(super) struct 撮影の条件 {
    pub(super) 出力名: &'static str,
    pub(super) フレーム数: 描画フレーム数,
}

pub(super) const タイトルの撮影: 撮影の条件 = 撮影の条件 {
    出力名: "title",
    フレーム数: 描画フレーム数::生成する(10),
};
pub(super) const プレイ中の撮影: 撮影の条件 = 撮影の条件 {
    出力名: "play",
    フレーム数: 描画フレーム数::生成する(120),
};
pub(super) const 目的地付近の撮影: 撮影の条件 = 撮影の条件 {
    出力名: "destination",
    フレーム数: 描画フレーム数::生成する(231),
};
pub(super) const 目的地付近の二度目の撮影: 撮影の条件 = 撮影の条件 {
    出力名: "destination_again",
    フレーム数: 描画フレーム数::生成する(231),
};
pub(super) const 終了確認の撮影: 撮影の条件 = 撮影の条件 {
    出力名: "quit_menu",
    フレーム数: 描画フレーム数::生成する(240),
};

/// 終了の決定まで進める条件。台本が251回目の更新で終了を決めるため、そこでイベントループが閉じて絵は残らない。
pub(super) const 終了までの実行: 撮影の条件 = 撮影の条件 {
    出力名: "quit",
    フレーム数: 描画フレーム数::生成する(300),
};

/// 台本を使わない対照。実ウィンドウの操作が1つも通らないことを見る。
pub(super) const 台本なしの実行: 撮影の条件 = 撮影の条件 {
    出力名: "no_script",
    フレーム数: 描画フレーム数::生成する(60),
};
