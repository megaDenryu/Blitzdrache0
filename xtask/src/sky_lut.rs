const 出力ディレクトリ: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("sky_lut");

pub fn 大気のベイク済み画像の更新を確認する(引数一覧: &[String]) -> ExitCode {
    let 時刻 = match 一日内秒を読む(引数一覧) {
        Ok(時刻) => 時刻,
        Err(理由) => {
            eprintln!("[xtask] sky-lut失敗: {理由}");
            return ExitCode::FAILURE;
        }
    };
    match 検収する(時刻.as_deref()) {
        Ok(要約) => {
            println!("[xtask] sky-lut成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] sky-lut失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

fn 検収する(一日内秒: Option<&str>) -> Result<String, 空のベイク済み画像の生成の検収エラー> {
    if !crate::gen_source_assets::検証用ソースアセットを生成して成否を返す() || !crate::compile_assets::地形世界を既定で生成する()
    {
        return Err(空のベイク済み画像の生成の検収エラー::検証用アセットを生成できなかった);
    }
    let 実行環境 = run::実行環境を作る(検証の出力ルート::既定().名前が指す置き場(出力ディレクトリ))?;

    let 停止 = run::描く(&実行環境, run::時計停止の実行名, run::条件::時計停止, 一日内秒)?;
    let 進行 = run::描く(&実行環境, run::時計進行の実行名, run::条件::時計進行, 一日内秒)?;
    let 合成なし = run::描く(&実行環境, run::合成なしの実行名, run::条件::合成なし, 一日内秒)?;
    let 寸法 = readback_size_match::三条件の寸法が一致することを確かめる(停止.画像(), 進行.画像(), 合成なし.画像())?;
    let 停止の列 = pass_count::読む(停止.報告(), "時計停止")?;
    let 進行の列 = pass_count::読む(進行.報告(), "時計進行")?;
    let 合成なしの列 = pass_count::読む(合成なし.報告(), "合成なし")?;

    let 間接照明の要約 = indirect_pass_count::三条件を確かめる(停止.報告(), 進行.報告(), 合成なし.報告())?;
    series_integrity::列の整合を確かめる(&停止の列, "時計停止")?;
    series_integrity::列の整合を確かめる(&進行の列, "時計進行")?;
    series_integrity::列の整合を確かめる(&合成なしの列, "合成なし")?;
    judgment::時計停止を判定する(&停止の列)?;
    judgment::時計進行を判定する(&進行の列)?;
    let 最遠距離 = farthest_distance::二条件が遠クリップと一致することを確かめる(停止.報告(), 進行.報告())?;
    let 停止点 = stop_point::停止点を判定する(合成なし.報告(), &合成なしの列, 合成なし.画像().バイト列(), 停止.画像().バイト列())?;
    let 計器 = gpu_time::区間を読む(停止.報告())?;

    let png = 停止.書き出し先().目視用の絵へ変換する()?;
    let 合成なしのpng = 合成なし.書き出し先().目視用の絵へ変換する()?;
    Ok(format!(
        "一日内時刻{}で、読み戻しの寸法は{}、時計停止は{}フレームで生成パス{}本(列の先頭{:?})、時計進行は{}フレームで生成パス{}本(うちスカイビューと空中遠近の2本を焼いたフレームが{}回)、最遠距離は{}、計器は{}、{}、停止点は{}、間接照明は{}、絵は{}と{}",
        一日内秒.map_or("既定(11時)".to_string(), |秒| format!("{秒}秒")),
        寸法,
        停止の列.数えたフレーム数,
        停止の列.総数,
        停止の列.先頭の並び(4),
        進行の列.数えたフレーム数,
        進行の列.総数,
        進行の列.本数の回数(2),
        最遠距離,
        計器.区間の並び,
        計器.予算との比較(),
        停止点,
        間接照明の要約,
        png.display(),
        合成なしのpng.display()
    ))
}
