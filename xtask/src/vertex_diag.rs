//! 頂点量の診断世界の対が計測の軸として成立していることを確かめる検収入口。
//! `shadow-probe`のvertex軸が読む2つの世界を同じ構図で描き、外形・配置・可視集合が固定されたまま
//! 原型のトポロジー量だけが変わっていることを見る。
//!
//! 確かめるのは4つである。距離区分別の可視数と描画発行の計数が完全に一致すること(配置も境界も段の選択も動いていない)、
//! 投入インデックス数の差から導いた群の個体数がその可視数と一致すること(増えたのは群のトポロジー量だけである)、
//! 群の影を外した絵の食い違いが上限以下であること、本番の絵の食い違いが上限以下であることである。
//!
//! **注意: 2つの画素判定は幾何同値性の検証ではなく、既知の実装状態からの回帰検知である。**
//! ここが判定するのは食い違った画素の数だけであり、その食い違いが輪郭に限られているかも、最大チャンネル差が
//! どれだけかも判定していない(どちらも数として報告するだけである)。上限は実測値へ余裕を足して置いてあり、
//! 「この幅に収まるなら着手時と同じ状態のままである」ことしか言わない。
//! 幾何同値性の主証拠は別にある。面を角と2本の辺ベクトルから解析的に構築していること(頂点が面の上に乗る根拠)、
//! 距離区分別の可視数と描画発行の計数が完全一致すること、群の投入インデックス数が個体あたり36と576の整数倍で
//! ちょうど16倍になることの3つである。
//!
//! 本番の絵に完全一致を求めないのは、細分化した頂点の座標が変換のあとで丸めのぶんだけ辺の上から外れうるためである。
//! 外れる量は最終桁の桁上がりであるが、低い太陽ではシャドウマップの深度比較がその桁に反応し、影の輪郭が1画素動きうる。
//! 群の影を外した絵を別に採るのは、群そのものの絵の食い違いと影が動いたぶんの食い違いを分けて読むためである。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」

mod count_check;
mod error;
mod pair;
mod pixel_check;
mod run;

use std::path::PathBuf;
use std::process::ExitCode;

use error::頂点量の診断の検収エラー;

use crate::acceptance::{判定の名前, 検収エラー};

const 出力ディレクトリ: &str = "target/vertex_diag";

/// この検収が焼く同居植生の密度。影が画面の広い範囲を覆う一方で1実行が短く済む点として選ぶ。
const チャンクあたり個体数: usize = 64;

/// 原型1段のインデックス数。粗い側は6面×2三角形の36、細かい側は6面×4×4格子×2三角形の576である。
/// 参照: `crates/blitz_asset_compiler/examples/generate_source_assets/vegetation_world/subdivided/faces.rs`
const 粗い側の1体あたりインデックス数: u64 = 36;
const 細かい側の1体あたりインデックス数: u64 = 576;

/// 群の影を外した絵の回帰検知の上限(割合の逆数)。着手時の実測は76画素であり、この幅は460画素である。
const 群の影なしで許す割合の逆数: usize = 2_000;

/// 本番の絵の回帰検知の上限(割合の逆数)。着手時の実測は2181画素であり、この幅は9216画素である。
/// 影の領域そのものが動けば影の画素数(実測で20万の桁)に比例した食い違いが出るため、この幅を超える。
const 本番で許す割合の逆数: usize = 100;

/// 導いた個体数が可視数と食い違えば、増えたのが群のトポロジー量だけであるという前提が崩れている。
const 導いた群の個体数: 判定の名前 = 判定の名前::定数から生成する("投入インデックス数の差から導いた群の個体数");

pub fn 頂点量の診断を確認する() -> ExitCode {
    match 検収する() {
        Ok(要約) => {
            println!("[xtask] vertex-diag成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] vertex-diag失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

fn 検収する() -> Result<String, 頂点量の診断の検収エラー> {
    if !crate::gen_source_assets::生成する() {
        return Err(頂点量の診断の検収エラー::検証用ソースアセットを生成できなかった);
    }
    let 出力先 = PathBuf::from(出力ディレクトリ);
    let 対 = pair::診断の対::焼く(&出力先, チャンクあたり個体数)?;

    let (影なしの粗い, 影なしの細かい) = 対.描き比べる("no_group_shadow", &["--no-instance-shadow"])?;
    let 影なしの食い違い = pixel_check::数える(&影なしの粗い.画像, &影なしの細かい.画像)?;
    影なしの食い違い.上限内か確かめる("群の影を外した絵", 群の影なしで許す割合の逆数)?;

    let (粗い, 細かい) = 対.描き比べる("production", &[])?;
    let 可視数 = count_check::計数の一致を検査する(&粗い.計数, &細かい.計数)?;
    let 増分 = 細かい側の1体あたりインデックス数 - 粗い側の1体あたりインデックス数;
    let 群の個体数 = count_check::群の個体数を導く(&粗い.計数, &細かい.計数, 増分)?;
    導いた群の個体数.綴りの一致を課す(&format!("{群の個体数:?}"), &format!("{可視数:?}"))?;
    let 食い違い = pixel_check::数える(&粗い.画像, &細かい.画像)?;
    食い違い.上限内か確かめる("本番の絵", 本番で許す割合の逆数)?;

    let 書き出し先 = 出力先.join("coarse_production");
    let 絵 = crate::raw_png::変換する(&書き出し先)
        .map_err(|破れ| 検収エラー::目視用の絵へ変換できなかった { 書き出し先, 破れ })?;
    Ok(format!(
        "距離区分別の可視数{可視数:?}と描画発行の計数が一致、群の投入インデックス数は粗い側が可視数×{粗い側の1体あたりインデックス数}で細かい側が可視数×{細かい側の1体あたりインデックス数}(ちょうど16倍)、群の影を外した絵は{}、本番の絵は{}、絵は{}",
        影なしの食い違い.要約(),
        食い違い.要約(),
        絵.display()
    ))
}
