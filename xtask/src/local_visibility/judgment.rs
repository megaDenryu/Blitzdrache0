//! 1つの形ぶんの行に対する判定。受け取るのは形と行、返すのは合否である。
//!
//! どの形にも共通して課すのは、正本と写しの誤差が許容に収まること・静止2フレームがバイト一致すること・
//! CPU側とGPU側の面の性質が離れないことの3つである。形ごとの性質は`shape_property`が別に見る。

use super::parse::形の行;
use super::tolerance;
use crate::acceptance::{判定の名前, 判定の破れ};

pub(super) fn 共通の判定を行う(行: &形の行) -> Result<(), 判定の破れ> {
    形ごとの判定名(行, "正本と写しの符号値の最大絶対誤差").上限を課す(行.最大絶対誤差, tolerance::最大絶対誤差の許容)?;
    形ごとの判定名(行, "正本と写しの符号値の誤差の第95百分位").上限を課す(行.第95百分位の誤差, tolerance::第95百分位誤差の許容)?;
    形ごとの判定名(行, "静止2フレームのGPU出力のバイト一致").真であることを課す(行.静止一致)?;
    形ごとの判定名(行, "正本と写しが一致した画素の数").上限を課す(行.一致画素数, 行.画素数)?;
    性質の一致を検査する(行)
}

/// CPU側とGPU側の面の性質が同じ物差しで同じ値を出していることを見る。片側だけで判定すると、
/// 正本が壊れて性質を失ったのか写しが壊れたのかを合否から読めない。
fn 性質の一致を検査する(行: &形の行) -> Result<(), 判定の破れ> {
    let 組一覧 = [
        ("最小符号値", 行.cpuの性質.最小符号値, 行.gpuの性質.最小符号値),
        ("符号値の幅", 行.cpuの性質.符号値の幅, 行.gpuの性質.符号値の幅),
        ("中央行の底", 行.cpuの性質.中央行の底, 行.gpuの性質.中央行の底),
        ("中央行の肩", 行.cpuの性質.中央行の肩, 行.gpuの性質.中央行の肩),
        ("中央行の縁", 行.cpuの性質.中央行の縁, 行.gpuの性質.中央行の縁),
        ("横の最大隣接差", 行.cpuの性質.横の最大隣接差, 行.gpuの性質.横の最大隣接差),
        ("縦の最大隣接差", 行.cpuの性質.縦の最大隣接差, 行.gpuの性質.縦の最大隣接差),
    ];
    for (名前, cpu, gpu) in 組一覧 {
        let 判定名 = 形ごとの判定名(行, &format!("{名前}のCPU{cpu}とGPU{gpu}の隔たり"));
        判定名.上限を課す(cpu.abs_diff(gpu), tolerance::性質の差の許容)?;
    }
    Ok(())
}

/// どの形の行に課した判定かを名前が言う。4つの形を1つずつ通すため、形を書かないと破れた行を特定できない。
fn 形ごとの判定名(行: &形の行, 見るもの: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{}の{見るもの}", 行.形))
}
