//! 1つの形ぶんの行に対する判定。受け取るのは形と行、返すのは合否である。
//!
//! どの形にも共通して課すのは、正本と写しの誤差が許容に収まること・静止2フレームがバイト一致すること・
//! CPU側とGPU側の面の性質が離れないことの3つである。形ごとの性質は`shape_property`が別に見る。

use super::parse::形の行;
use super::tolerance;

pub(super) fn 共通の判定を行う(行: &形の行) -> Result<(), String> {
    if 行.最大絶対誤差 > tolerance::最大絶対誤差の許容 {
        return Err(format!(
            "{}の最大絶対誤差が{}符号値で許容{}を超えた",
            行.形,
            行.最大絶対誤差,
            tolerance::最大絶対誤差の許容
        ));
    }
    if 行.p95誤差 > tolerance::第95百分位誤差の許容 {
        return Err(format!(
            "{}のp95誤差が{}符号値で許容{}を超えた",
            行.形,
            行.p95誤差,
            tolerance::第95百分位誤差の許容
        ));
    }
    if !行.静止一致 {
        return Err(format!("{}で静止2フレームのGPU出力がバイト一致しなかった", 行.形));
    }
    if 行.一致画素数 > 行.画素数 {
        return Err(format!("{}の一致画素数{}が画素数{}を超えた", 行.形, 行.一致画素数, 行.画素数));
    }
    性質の一致を検査する(行)
}

/// CPU側とGPU側の面の性質が同じ物差しで同じ値を出していることを見る。片側だけで判定すると、
/// 正本が壊れて性質を失ったのか写しが壊れたのかを合否から読めない。
fn 性質の一致を検査する(行: &形の行) -> Result<(), String> {
    let 組一覧 = [
        ("最小符号値", 行.cpuの性質.最小符号値, 行.gpuの性質.最小符号値),
        ("符号値の幅", 行.cpuの性質.符号値の幅, 行.gpuの性質.符号値の幅),
        ("中央行の底", 行.cpuの性質.中央行の底, 行.gpuの性質.中央行の底),
        ("中央行の肩", 行.cpuの性質.中央行の肩, 行.gpuの性質.中央行の肩),
        ("中央行の縁", 行.cpuの性質.中央行の縁, 行.gpuの性質.中央行の縁),
        ("横の最大隣接差", 行.cpuの性質.横の最大隣接差, 行.gpuの性質.横の最大隣接差),
        ("縦の最大隣接差", 行.cpuの性質.縦の最大隣接差, 行.gpuの性質.縦の最大隣接差),
    ];
    for (名前, cpu, gpu) in 組一覧 {
        if cpu.abs_diff(gpu) > tolerance::性質の差の許容 {
            return Err(format!(
                "{}の{名前}がCPU{cpu}とGPU{gpu}で{}符号値離れた(許容{})",
                行.形,
                cpu.abs_diff(gpu),
                tolerance::性質の差の許容
            ));
        }
    }
    Ok(())
}
