//! 3枚のHDR画像が同じ構図で撮れているかの検査。受け取るのは3枚、返すのは合否である。
//!
//! これが要るのは、3枚が別々のプロセスで撮られるためである。プロセスをまたいで同じ絵になることを、アプリは
//! 保証していない。`--frames`の実行は実ウィンドウを作り、そのウィンドウへ届いた入力イベント(ドラッグ・ホイール・
//! 移動キー)が毎フレームカメラへ適用される(`crates/blitz_app/src/app/frame.rs`の`カメラ.更新する`)。入力が届くか
//! どうかは実行環境で変わるため、カメラの姿勢がプロセスごとに違う絵になりうる。
//!
//! **2026-08-05の実測で、同じ引数の60回の起動のうち2回、板の位置と大きさが違う絵が出た。** 板の並びは
//! 画面中央から約3.4パーセント広がり、上段は約9パーセント縮んで下段は約5パーセント伸びた。焼き上げの違いでは
//! 説明できない(同じ引数の絵はフレーム数2から24まで1バイトも変わらない)。カメラの姿勢の違いだけがこの形を作る。
//!
//! 構図が違う3枚をそのまま測ると、板が動いたぶんの差が局所可視度の効きとして数えられ、入口が別の理由で落ちる。
//! 数を採る前にここで落とし、失敗の理由を「構図が揃っていない」と名指しする。

use super::hdr_image::{HDR画像, 画素あたり成分数};

/// 3枚の構図が揃っていることを確かめる。
///
/// 局所可視度は拡散間接照度だけへ掛かるため、可視度を下げて暗くなることはあっても、描かれていなかった画素が
/// 描かれることは無い。したがって描かれた画素の集合は可視度が上がるほど広がるか等しいかのどちらかであり、
/// 全遮蔽から中間、中間から遮蔽なしへ向かって包含が成り立つ。構図が違う3枚ではこの包含が両向きに破れる。
pub(super) fn 構図の一致を確かめる(遮蔽なし: &HDR画像, 中間: &HDR画像, 全遮蔽: &HDR画像) -> Result<(), String> {
    包含を確かめる(全遮蔽, 中間, "全遮蔽", "中間")?;
    包含を確かめる(中間, 遮蔽なし, "中間", "遮蔽なし")
}

/// 狭いほうの描かれた画素が広いほうに含まれることを確かめる。
fn 包含を確かめる(狭い: &HDR画像, 広い: &HDR画像, 狭い名: &str, 広い名: &str) -> Result<(), String> {
    let はみ出し = (0..狭い.画素数).filter(|&位置| 描かれたか(狭い, 位置) && !描かれたか(広い, 位置)).count();
    if はみ出し == 0 {
        return Ok(());
    }
    Err(format!(
        "3枚の構図が揃っていない: 局所可視度{狭い名}では描かれ{広い名}では描かれていない画素が{はみ出し}件ある(カメラの姿勢がプロセスごとに違う疑いがある)"
    ))
}

/// その画素に何かが描かれたか。背景はクリア色を黒へ落としてあるため、黒でない画素はシーンの画素段が描いた画素である。
fn 描かれたか(画像: &HDR画像, 位置: usize) -> bool {
    let 先頭 = 位置 * 画素あたり成分数;
    画像.成分列[先頭] != 0.0 || 画像.成分列[先頭 + 1] != 0.0 || 画像.成分列[先頭 + 2] != 0.0
}

#[cfg(test)]
mod tests {
    use super::*;

    fn 画像(明るさ一覧: [f32; 3]) -> HDR画像 {
        let mut 成分列 = Vec::new();
        for 明るさ in 明るさ一覧 {
            成分列.extend_from_slice(&[明るさ, 明るさ, 明るさ, 1.0]);
        }
        HDR画像 {
            画素数: 明るさ一覧.len(),
            成分列,
        }
    }

    #[test]
    fn 可視度が上がるほど描かれた画素が広がるなら通る() {
        let 全遮蔽 = 画像([0.0, 0.0, 0.5]);
        let 中間 = 画像([0.0, 0.2, 0.6]);
        let 遮蔽なし = 画像([0.1, 0.4, 0.7]);
        assert!(構図の一致を確かめる(&遮蔽なし, &中間, &全遮蔽).is_ok());
    }

    #[test]
    fn 描かれた画素が消えたら落ちる() {
        let 全遮蔽 = 画像([0.3, 0.0, 0.5]);
        let 中間 = 画像([0.0, 0.2, 0.6]);
        let 遮蔽なし = 画像([0.1, 0.4, 0.7]);
        assert!(構図の一致を確かめる(&遮蔽なし, &中間, &全遮蔽).is_err());
    }

    #[test]
    fn 中間と遮蔽なしの間で消えても落ちる() {
        let 全遮蔽 = 画像([0.0, 0.0, 0.5]);
        let 中間 = 画像([0.0, 0.2, 0.6]);
        let 遮蔽なし = 画像([0.1, 0.0, 0.7]);
        assert!(構図の一致を確かめる(&遮蔽なし, &中間, &全遮蔽).is_err());
    }
}
