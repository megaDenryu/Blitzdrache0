//! blitz_appが出した局所可視性の照合行を数の並びへ直す工程。受け取るのは終了時報告、返すのは1行ぶんの値である。
//! 判定はこの並びだけを見る。
//!
//! 行が1本も無いことを失敗にするのは、注入も報告も行われなかった実行を「全項目が通った」と読み替えないためである。
//! 見送りの行を失敗にするのも同じで、読み戻しが成立しなかった実行が黙って通ることを防ぐ。
//!
//! 見送りの綴りを行の原文から探すのは、見送りの行が他の項目を1つも持たないためである。鍵で読もうとすると、
//! 「読み戻しが見送られた」でなく「画素数の鍵が無い」という別の理由で落ちる。

use crate::acceptance::{判定の名前, 報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

/// 1つの形ぶんの照合結果。符号値の単位は8ビット無符号正規化の1段である。
pub(super) struct 形の行 {
    pub(super) 形: String,
    pub(super) 画素数: u64,
    pub(super) 一致画素数: u64,
    pub(super) 最大絶対誤差: u64,
    pub(super) p95誤差: u64,
    pub(super) 静止一致: bool,
    pub(super) gpuの性質: 面の性質,
    pub(super) cpuの性質: 面の性質,
}

/// 面1枚ぶんの性質。CPU正本の凹面の検査と同じ枠組みで採った値である。
pub(super) struct 面の性質 {
    pub(super) 最小符号値: u64,
    pub(super) 符号値の幅: u64,
    pub(super) 中央行の底: u64,
    pub(super) 中央行の肩: u64,
    pub(super) 中央行の縁: u64,
    pub(super) 横の最大隣接差: u64,
    pub(super) 縦の最大隣接差: u64,
}

const 行の見出し: 報告の見出し = 報告の見出し::定数から生成する("局所可視性行 ");
/// 読み戻しが成立しなかった実行の行に現れる綴り。正本は`crates/blitz_app/src/reports/local_visibility.rs`である。
const 読み戻しの見送りの綴り: &str = "読み戻し=見送り";
/// この報告の行は全項目が「鍵=値」の形で並ぶ。
const 値の結ばれ方: 鍵に値が結ばれる形 = 鍵に値が結ばれる形::等号の後ろが値である;

pub(super) fn 形の行を取り出す(報告: &終了時報告) -> Result<形の行, 検収エラー> {
    let 行 = 報告.見出しの1行(&行の見出し)?;
    見送りの判定名(&行).零件であることを課す(u64::from(行.原文().contains(読み戻しの見送りの綴り)))?;
    Ok(形の行 {
        形: 行.鍵に結ばれた綴り(&鍵を組む("形"), 値の結ばれ方)?,
        画素数: 数を読む(&行, "画素数")?,
        一致画素数: 数を読む(&行, "一致画素数")?,
        最大絶対誤差: 数を読む(&行, "最大絶対誤差")?,
        p95誤差: 数を読む(&行, "p95誤差")?,
        静止一致: 行.鍵に結ばれた真偽(&鍵を組む("静止一致"), 値の結ばれ方)?,
        gpuの性質: 性質を読む(&行, "GPU")?,
        cpuの性質: 性質を読む(&行, "CPU")?,
    })
}

fn 性質を読む(行: &報告の行, 接頭辞: &str) -> Result<面の性質, 検収エラー> {
    Ok(面の性質 {
        最小符号値: 数を読む(行, &format!("{接頭辞}最小符号値"))?,
        符号値の幅: 数を読む(行, &format!("{接頭辞}符号値の幅"))?,
        中央行の底: 数を読む(行, &format!("{接頭辞}中央行の底"))?,
        中央行の肩: 数を読む(行, &format!("{接頭辞}中央行の肩"))?,
        中央行の縁: 数を読む(行, &format!("{接頭辞}中央行の縁"))?,
        横の最大隣接差: 数を読む(行, &format!("{接頭辞}横の最大隣接差"))?,
        縦の最大隣接差: 数を読む(行, &format!("{接頭辞}縦の最大隣接差"))?,
    })
}

fn 数を読む(行: &報告の行, 鍵の綴り: &str) -> Result<u64, 検収エラー> {
    行.鍵に結ばれた数(&鍵を組む(鍵の綴り), 値の結ばれ方)
}

fn 鍵を組む(綴り: &str) -> 報告の行の鍵 {
    報告の行の鍵::組み立てた綴りから生成する(綴り.to_string())
}

/// 見送りの行そのものを綴りへ入れるのは、blitz_appが見送った理由をその行に書いているためである。
fn 見送りの判定名(行: &報告の行) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("局所可視性の照合行の読み戻しの見送り(行「{}」)", 行.原文()))
}
