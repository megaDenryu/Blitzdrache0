//! blitz_appが出した局所可視性の照合行を数の並びへ直す工程。受け取るのは標準出力、返すのは1行ぶんの値である。
//! 判定はこの並びだけを見る。
//!
//! 行が1本も無いことを失敗にするのは、注入も報告も行われなかった実行を「全項目が通った」と読み替えないためである。
//! 見送りの行を失敗にするのも同じで、読み戻しが成立しなかった実行が黙って通ることを防ぐ。

/// 1つの形ぶんの照合結果。符号値の単位は8ビット無符号正規化の1段である。
pub(super) struct 形の行 {
    pub(super) 形: String,
    pub(super) 画素数: u64,
    pub(super) 一致画素数: u64,
    pub(super) 最大絶対誤差: u64,
    pub(super) p95誤差: u64,
    pub(super) 静止一致: bool,
    pub(super) gpuの性質: 面の性質,
    pub(super) cpuの性質: 面の性質,
}

/// 面1枚ぶんの性質。CPU正本の凹面の検査と同じ枠組みで採った値である。
pub(super) struct 面の性質 {
    pub(super) 最小符号値: u64,
    pub(super) 符号値の幅: u64,
    pub(super) 中央行の底: u64,
    pub(super) 中央行の肩: u64,
    pub(super) 中央行の縁: u64,
    pub(super) 横の最大隣接差: u64,
    pub(super) 縦の最大隣接差: u64,
}

const 行の見出し: &str = "局所可視性行 ";

pub(super) fn 形の行を取り出す(標準出力: &str) -> Result<形の行, String> {
    let 行 = 標準出力
        .lines()
        .map(str::trim)
        .find(|行| 行.starts_with(行の見出し))
        .ok_or_else(|| "局所可視性の照合行が1本も出ていない".to_string())?;
    if 行.contains("読み戻し=見送り") {
        return Err(format!("読み戻しが見送られた: {行}"));
    }
    Ok(形の行 {
        形: 語を取り出す(行, "形=")?.to_string(),
        画素数: 数を読む(行, "画素数=")?,
        一致画素数: 数を読む(行, "一致画素数=")?,
        最大絶対誤差: 数を読む(行, "最大絶対誤差=")?,
        p95誤差: 数を読む(行, "p95誤差=")?,
        静止一致: 真偽を読む(行, "静止一致=")?,
        gpuの性質: 性質を読む(行, "GPU")?,
        cpuの性質: 性質を読む(行, "CPU")?,
    })
}

fn 性質を読む(行: &str, 接頭辞: &str) -> Result<面の性質, String> {
    Ok(面の性質 {
        最小符号値: 数を読む(行, &format!("{接頭辞}最小符号値="))?,
        符号値の幅: 数を読む(行, &format!("{接頭辞}符号値の幅="))?,
        中央行の底: 数を読む(行, &format!("{接頭辞}中央行の底="))?,
        中央行の肩: 数を読む(行, &format!("{接頭辞}中央行の肩="))?,
        中央行の縁: 数を読む(行, &format!("{接頭辞}中央行の縁="))?,
        横の最大隣接差: 数を読む(行, &format!("{接頭辞}横の最大隣接差="))?,
        縦の最大隣接差: 数を読む(行, &format!("{接頭辞}縦の最大隣接差="))?,
    })
}

fn 語を取り出す<'a>(行: &'a str, 語の見出し: &str) -> Result<&'a str, String> {
    行.split_whitespace()
        .find_map(|語| 語.strip_prefix(語の見出し))
        .ok_or_else(|| format!("行に「{語の見出し}」が無い: {行}"))
}

fn 数を読む(行: &str, 語の見出し: &str) -> Result<u64, String> {
    let 語 = 語を取り出す(行, 語の見出し)?;
    語.parse::<u64>()
        .map_err(|誤り| format!("「{語の見出し}」の値を整数として読めない({語}): {誤り}"))
}

fn 真偽を読む(行: &str, 語の見出し: &str) -> Result<bool, String> {
    match 語を取り出す(行, 語の見出し)? {
        "真" => Ok(true),
        "偽" => Ok(false),
        その他 => Err(format!("「{語の見出し}」の値が真偽でない: {その他}")),
    }
}
