//! 判定が使う許容と閾値。触れる状態を持たず、担うのは値とその根拠を1箇所へ置くことだけである。
//!
//! 単位はすべて8ビット無符号正規化の符号値であり、CPU正本の性質検査が実数で置いた閾値をこの目盛りへ写してある
//! (`crates/blitz_render/src/local_visibility/local_visibility_tests/concave_tests.rs`)。写して使うのは、
//! 正本で立った性質がGPUでも残っているかを同じ物差しで読むためである。閾値を別に決めると、正本とGPUの
//! どちらが動いたのかを合否から読めない。

/// 正本と写しの符号値の最大絶対誤差の許容。2026-08-05の実測は平面0・段差2・球0・凹面2である。
/// 全画素のバイト一致を課さないのは、写しが単精度で組まれ、正本も単精度で組みながら一部の中間だけを
/// 倍精度で作るためである。
pub(super) const 最大絶対誤差の許容: u64 = 2;

/// 誤差の第95百分位の許容。実測は4形とも0であり、丸めの差が全体に広がっていないことをこの値が守る。
pub(super) const 第95百分位誤差の許容: u64 = 1;

/// 面の性質の値がCPU側とGPU側で離れてよい量。突き合わせの許容と同じ根拠であり、実測は4形とも0である。
pub(super) const 性質の差の許容: u64 = 2;

/// 遮蔽が出たと認める最小符号値の上限。正本の検査の0.95を符号値へ写した値である(0.95×255=242.25)。
pub(super) const 遮蔽が出たと認める上限: u64 = 242;

/// 可視度が場所によって変わったと認める符号値の幅の下限。正本の検査の0.05を写した値である(0.05×255=12.75)。
pub(super) const 場所で変わったと認める幅の下限: u64 = 12;

/// 面の上で認める隣り合う画素の差の上限。正本の検査の0.1を写した値である(0.1×255=25.5)。
/// 標本数16の1本ぶん(0.0625→15.9)より緩く、段差の境界で出る0.2625(→66.9)よりひと桁小さい位置にある。
pub(super) const 面の上で認める差の上限: u64 = 25;

/// 底と肩の間で認める隔たりの下限。正本の検査の0.05を写した値である。
pub(super) const 底と肩の隔たりの下限: u64 = 12;

/// 肩と縁の間で認める隔たりの下限。正本の検査の0.005を写した値である(0.005×255=1.275)。
pub(super) const 肩と縁の隔たりの下限: u64 = 1;
