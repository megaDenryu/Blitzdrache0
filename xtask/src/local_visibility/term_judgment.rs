//! 項別の実測に対する判定。受け取るのは実測、返すのは合否である。
//!
//! 4つを同時に課すのは、どれか1つだけでは掛かる先を決められないためである。動いた画素があるだけでは
//! 全部の項に掛けている実装でも通り、不変の画素があるだけでは1画素も掛けていない実装でも通る。
//! 向きと線形性を足して初めて「拡散間接だけに、可視度そのものの比で掛かっている」と言える。

use super::term_measure::項別の実測;

/// 明るいまま不変の画素の最大輝度に課す下限。この値を超える画素が在ることが、直接光か鏡面間接を実際に
/// 受けている画素が不変であることの証拠になる。2026-08-05の実測は0.873である。
const 不変の画素に課す輝度の下限: f32 = 0.1;

/// 中間の値での線形性に課す相対ずれの上限。半精度で記録したHDR中間画像の相対精度は約1000分の1であり、
/// この上限はその10倍の余裕を取る。実測は0.00089である。
const 線形性の許容: f32 = 0.01;

pub(super) fn 判定する(実測: &項別の実測) -> Result<(), String> {
    if 実測.動いた画素数 == 0 {
        return Err("局所可視度を0と1で変えても1画素も動かなかった(掛け算が届いていない)".to_string());
    }
    if 実測.明るいまま不変の画素数 == 0 {
        return Err("明るいまま不変の画素が1つも無い(拡散間接以外の項にも掛かっている疑いがある)".to_string());
    }
    if 実測.不変の画素の最大輝度 <= 不変の画素に課す輝度の下限 {
        return Err(format!(
            "不変の画素の最大輝度が{:.4}で下限{不変の画素に課す輝度の下限}を超えない(不変なのは暗い画素だけである)",
            実測.不変の画素の最大輝度
        ));
    }
    if 実測.暗くなった成分数 > 0 {
        return Err(format!(
            "局所可視度を上げて暗くなった成分が{}件ある(掛かる向きが逆である)",
            実測.暗くなった成分数
        ));
    }
    if 実測.中間で外れた不変画素数 > 0 {
        return Err(format!("両端で不変なのに中間の値でだけ動いた画素が{}件ある", 実測.中間で外れた不変画素数));
    }
    if 実測.線形性の最大相対ずれ > 線形性の許容 {
        return Err(format!(
            "中間の値の線形性が最大{:.5}ずれた(許容{線形性の許容})",
            実測.線形性の最大相対ずれ
        ));
    }
    Ok(())
}
