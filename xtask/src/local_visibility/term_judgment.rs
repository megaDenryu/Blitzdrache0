//! 項別の実測に対する判定。受け取るのは実測、返すのは合否である。
//!
//! 4つを同時に課すのは、どれか1つだけでは掛かる先を決められないためである。動いた画素があるだけでは
//! 全部の項に掛けている実装でも通り、不変の画素があるだけでは1画素も掛けていない実装でも通る。
//! 向きと線形性を足して初めて「拡散間接だけに、可視度そのものの比で掛かっている」と言える。
//!
//! 輝度の下限だけを真偽で課すのは、この判定が下限に等しい実測を破れの側へ置くためである。下限の口は
//! 等号を通すため、そのまま置き換えると「不変なのは暗い画素だけである」実行が境界でだけ通る。

use super::term_measure::項別の実測;
use crate::acceptance::{判定の名前, 判定の破れ};

/// 明るいまま不変の画素の最大輝度に課す下限。この値を超える画素が在ることが、直接光か鏡面間接を実際に
/// 受けている画素が不変であることの証拠になる。2026-08-05の実測は0.873である。
const 不変の画素に課す輝度の下限: f32 = 0.1;

/// 中間の値での線形性に課す相対ずれの上限。半精度で記録したHDR中間画像の相対精度は約1000分の1であり、
/// この上限はその10倍の余裕を取る。実測は0.00089である。
const 線形性の許容: f32 = 0.01;

const 局所可視度で動いた画素: 判定の名前 =
    判定の名前::定数から生成する("局所可視度を0と1で変えて動いた画素(1画素も動かないなら掛け算が届いていない)");
const 明るいまま不変の画素: 判定の名前 =
    判定の名前::定数から生成する("明るいまま不変の画素(1つも無いなら拡散間接以外の項にも掛かっている疑いがある)");
const 上げて暗くなった成分: 判定の名前 = 判定の名前::定数から生成する("局所可視度を上げて暗くなった成分(掛かる向きが逆である)");
const 両端で不変なのに中間で動いた画素: 判定の名前 = 判定の名前::定数から生成する("両端で不変なのに中間の値でだけ動いた画素");
const 中間の値の線形性の相対ずれ: 判定の名前 = 判定の名前::定数から生成する("中間の値の線形性の相対ずれ");

pub(super) fn 判定する(実測: &項別の実測) -> Result<(), 判定の破れ> {
    if 実測.動いた画素数 == 0 {
        return Err(局所可視度で動いた画素.あるはずのものが無い破れ());
    }
    if 実測.明るいまま不変の画素数 == 0 {
        return Err(明るいまま不変の画素.あるはずのものが無い破れ());
    }
    不変の画素の輝度の判定名(実測).真であることを課す(実測.不変の画素の最大輝度 > 不変の画素に課す輝度の下限)?;
    上げて暗くなった成分.零件であることを課す(実測.暗くなった成分数)?;
    両端で不変なのに中間で動いた画素.零件であることを課す(実測.中間で外れた不変画素数)?;
    中間の値の線形性の相対ずれ.上限を課す(f64::from(実測.線形性の最大相対ずれ), f64::from(線形性の許容))
}

/// 実測の輝度を綴りへ入れるのは、真偽で課す判定が比べた数を文面へ出せないためである。
fn 不変の画素の輝度の判定名(実測: &項別の実測) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "不変の画素の最大輝度{:.4}が下限{不変の画素に課す輝度の下限}を超えること(超えないなら不変なのは暗い画素だけである)",
        実測.不変の画素の最大輝度
    ))
}
