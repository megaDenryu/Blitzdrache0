//! 局所可視度を一定値へ固定した1条件ぶんの起動の指定。受け取るのは符号値、返すのは実行環境へ渡す起動指定である。
//! 起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! 間接照明の検収世界を使うのは、金属と誘電体の板が同じ画面に並ぶ唯一の世界だからである。金属の板は拡散の
//! 取り分が0であるため拡散間接照度を持たず、局所可視度を掛けても1ビットも動かない。同じ画面に動く板と動かない板が
//! 揃っていることが、掛かる先が拡散間接だけであることの反証になる。
//!
//! シーンパスのクリア色を黒へ落とすのは、シーン画素段を1度も通らない背景を「局所可視度に不変な画素」として
//! 数えないためである。`--auto-exposure-probe`はクリア色を線形RGBへ置き換える起動指定であり、この実行では
//! 自動露出の集計を1つも読まない。
//!
//! 圧縮前のHDRを読むのは、明るさの圧縮とsRGB符号化を通った後の8ビット値から通す前の値を復元できないためである。
//! 項ごとの比は線形の放射輝度でしか成り立たない。

use std::path::PathBuf;

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収の実行名, 検収エラー, 検収シーン名,
};
use crate::verify::検証の出力ルート;

const シーン名: 検収シーン名 = 検収シーン名::生成する("indirect_probe");
/// 描くフレーム数。間接照明の焼き上げが定常へ入る本数であり、`indirect-probe`の各条件と揃えてある。
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(12);
/// 昼。太陽が高く、板が直接光と鏡面間接の両方を受ける時刻である。夜で測ると直接光が0になり、
/// 直接光が不変であることを1つも見られない。
const 昼の一日内秒: &str = "43200";

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::パスから生成する(
            検証の出力ルート::既定().名前が指す置き場(crate::compile_assets::板の世界の実行時形式の置き場),
        ),
        出力ディレクトリ,
    )
}

/// 符号値ごとの書き出しの基準名。絵のファイル名になり、失敗の文面もこの名前で実行を名指す。
pub(super) fn 実行名を組む(符号値: u8) -> Result<検収の実行名, 検収エラー> {
    検収の実行名::生成する(&format!("ao{符号値}"))
}

pub(super) fn 符号値の起動指定を組み立てる(符号値: u8) -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数)
        .値を持つ選択肢を足す("--time-of-day", 昼の一日内秒)
        .選択肢を足す("--no-sky")
        .値を持つ選択肢を足す("--auto-exposure-probe", "0,0,0")
        .値を持つ選択肢を足す("--local-visibility-fixed", &符号値.to_string())
}
