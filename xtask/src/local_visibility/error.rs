//! 局所可視性補正の検収が返す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。
//! 様式は`acceptance/error.rs`と`depth_prepass_cost/error.rs`に倣う。
//!
//! 検収の器の破れと判定の破れを枝で内包するのは、この入口が起動と読み取りと判定を一続きに通すためである。
//! 3つを別の型で返すと、通す側が段ごとに変換を書くことになる。
//!
//! 目視見本の世界の用意とアセットの生成をここが持つのは、どちらも判定でも報告の読み取りでもないためである。
//! 人が読む1文へ写すのは`display`が持つ。

mod display;

use crate::acceptance::{判定の破れ, 検収エラー};

#[derive(Debug)]
pub(super) enum 局所可視性補正の検収エラー {
    検収の器が破れた(検収エラー),
    判定が破れた(判定の破れ),
    目視見本世界を用意できなかった(crate::world_setup::検収世界の用意の破れ),
    間接照明の検収世界のアセットを生成できなかった,
}

impl std::error::Error for 局所可視性補正の検収エラー {}

impl From<検収エラー> for 局所可視性補正の検収エラー {
    fn from(破れ: 検収エラー) -> Self {
        Self::検収の器が破れた(破れ)
    }
}

impl From<判定の破れ> for 局所可視性補正の検収エラー {
    fn from(破れ: 判定の破れ) -> Self {
        Self::判定が破れた(破れ)
    }
}
