//! 形ごとに固有の性質の判定。受け取るのは形の行、返すのは合否である。判定はGPU側の性質だけを見る。
//!
//! GPU側を見るのは、この検査の目的が「正本で立った性質が写しでも残っているか」だからである。CPU側との
//! 一致は`judgment`が別に見ており、2つを合わせて初めて「同じ性質が両側に在る」と言える。
//!
//! 平面と球に遮蔽が出ないことを対に置くのは、段差と凹面の判定が定数を返す実装でも通ってしまうためである
//! (正本の性質検査と同じ構え)。

use super::parse::形の行;
use super::tolerance;

pub(super) fn 形の性質を検査する(行: &形の行) -> Result<(), String> {
    match 行.形.as_str() {
        "平面" | "球" => 遮蔽が出ないことを検査する(行),
        "段差" => 片側だけが暗くなることを検査する(行),
        "凹面" => 連続に薄まることを検査する(行),
        その他 => Err(format!("知らない形の行が出た: {その他}")),
    }
}

/// 平面は遮蔽が起きない形、球は凸であるため自分を遮蔽しない形である。どちらも全画素が遮蔽なしになる。
fn 遮蔽が出ないことを検査する(行: &形の行) -> Result<(), String> {
    let 性質 = &行.gpuの性質;
    if 性質.最小符号値 <= tolerance::遮蔽が出たと認める上限 {
        return Err(format!("{}に遮蔽が生まれた(最小符号値{})", 行.形, 性質.最小符号値));
    }
    if 性質.符号値の幅 > tolerance::場所で変わったと認める幅の下限 {
        return Err(format!("{}で可視度が場所によって変わった(符号値の幅{})", 行.形, 性質.符号値の幅));
    }
    Ok(())
}

/// 段差は境界の奥側だけが暗くなる形である。中央行の底(境界の列)が肩より濃いことがその現れである。
fn 片側だけが暗くなることを検査する(行: &形の行) -> Result<(), String> {
    let 性質 = &行.gpuの性質;
    if 性質.最小符号値 > tolerance::遮蔽が出たと認める上限 {
        return Err(format!("段差に遮蔽が生まれなかった(最小符号値{})", 性質.最小符号値));
    }
    if 性質.中央行の底 + tolerance::底と肩の隔たりの下限 >= 性質.中央行の肩 {
        return Err(format!("段差の接触側{}が凸側{}より十分に濃くない", 性質.中央行の底, 性質.中央行の肩));
    }
    Ok(())
}

/// 凹面は法線が連続に変わりながら遮蔽が生まれる唯一の形である。可視度が場所によって変わり、底から縁へ
/// 向かって薄まり、面の上に飛びが出ないことの3つを同時に見る。
fn 連続に薄まることを検査する(行: &形の行) -> Result<(), String> {
    let 性質 = &行.gpuの性質;
    if 性質.最小符号値 > tolerance::遮蔽が出たと認める上限 {
        return Err(format!("凹面に遮蔽が生まれなかった(最小符号値{})", 性質.最小符号値));
    }
    if 性質.符号値の幅 <= tolerance::場所で変わったと認める幅の下限 {
        return Err(format!("凹面の可視度が場所によって変わらない(符号値の幅{})", 性質.符号値の幅));
    }
    if 性質.中央行の底 + tolerance::底と肩の隔たりの下限 >= 性質.中央行の肩 {
        return Err(format!("凹面の底{}が肩{}より十分に濃くない", 性質.中央行の底, 性質.中央行の肩));
    }
    if 性質.中央行の肩 + tolerance::肩と縁の隔たりの下限 >= 性質.中央行の縁 {
        return Err(format!("凹面の肩{}が縁{}より十分に濃くない", 性質.中央行の肩, 性質.中央行の縁));
    }
    let 最大の差 = 性質.横の最大隣接差.max(性質.縦の最大隣接差);
    if 最大の差 > tolerance::面の上で認める差の上限 {
        return Err(format!("凹面の上で可視度が跳んだ(最大の隣接差{最大の差}符号値)"));
    }
    Ok(())
}
