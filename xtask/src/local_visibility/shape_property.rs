//! 形ごとに固有の性質の判定。受け取るのは形の行、返すのは合否である。判定はGPU側の性質だけを見る。
//!
//! GPU側を見るのは、この検査の目的が「正本で立った性質が写しでも残っているか」だからである。CPU側との
//! 一致は`judgment`が別に見ており、2つを合わせて初めて「同じ性質が両側に在る」と言える。
//!
//! 平面と球に遮蔽が出ないことを対に置くのは、段差と凹面の判定が定数を返す実装でも通ってしまうためである
//! (正本の性質検査と同じ構え)。
//!
//! 隔たりと「変わったこと」を真偽で課すのは、正本の検査が境界の等号を破れの側へ置いているためである。
//! 上限と下限の口は等号を通すため、そのまま置き換えると境界の1符号値ぶんだけ判定が緩む。

use super::parse::形の行;
use super::tolerance;
use crate::acceptance::{判定の名前, 判定の破れ};

/// 判定できる形の名前。正本は`crates/blitz_app/src/reports/local_visibility.rs`が出す綴りである。
const 判定できる形の名前: &str = "平面・段差・球・凹面のいずれか";

pub(super) fn 形の性質を検査する(行: &形の行) -> Result<(), 判定の破れ> {
    match 行.形.as_str() {
        "平面" | "球" => 遮蔽が出ないことを検査する(行),
        "段差" => 片側だけが暗くなることを検査する(行),
        "凹面" => 連続に薄まることを検査する(行),
        その他 => 判定の名前::定数から生成する("報告に出た形の名前").綴りの一致を課す(その他, 判定できる形の名前),
    }
}

/// 平面は遮蔽が起きない形、球は凸であるため自分を遮蔽しない形である。どちらも全画素が遮蔽なしになる。
fn 遮蔽が出ないことを検査する(行: &形の行) -> Result<(), 判定の破れ> {
    let 性質 = &行.gpuの性質;
    形ごとの判定名(行, &format!("遮蔽が生まれていないこと(最小符号値{})", 性質.最小符号値))
        .真であることを課す(性質.最小符号値 > tolerance::遮蔽が出たと認める上限)?;
    形ごとの判定名(行, "場所による可視度の符号値の幅").上限を課す(性質.符号値の幅, tolerance::場所で変わったと認める幅の下限)
}

/// 段差は境界の奥側だけが暗くなる形である。中央行の底(境界の列)が肩より濃いことがその現れである。
fn 片側だけが暗くなることを検査する(行: &形の行) -> Result<(), 判定の破れ> {
    遮蔽が生まれたことを検査する(行)?;
    底が肩より濃いことを検査する(行, "接触側", "凸側")
}

/// 凹面は法線が連続に変わりながら遮蔽が生まれる唯一の形である。可視度が場所によって変わり、底から縁へ
/// 向かって薄まり、面の上に飛びが出ないことの3つを同時に見る。
fn 連続に薄まることを検査する(行: &形の行) -> Result<(), 判定の破れ> {
    let 性質 = &行.gpuの性質;
    遮蔽が生まれたことを検査する(行)?;
    形ごとの判定名(行, &format!("場所によって可視度が変わったこと(符号値の幅{})", 性質.符号値の幅))
        .真であることを課す(性質.符号値の幅 > tolerance::場所で変わったと認める幅の下限)?;
    底が肩より濃いことを検査する(行, "底", "肩")?;
    形ごとの判定名(行, &format!("肩{}が縁{}より十分に濃いこと", 性質.中央行の肩, 性質.中央行の縁))
        .真であることを課す(性質.中央行の肩 + tolerance::肩と縁の隔たりの下限 < 性質.中央行の縁)?;
    let 最大の差 = 性質.横の最大隣接差.max(性質.縦の最大隣接差);
    形ごとの判定名(行, "面の上で隣り合う画素の可視度の差").上限を課す(最大の差, tolerance::面の上で認める差の上限)
}

fn 遮蔽が生まれたことを検査する(行: &形の行) -> Result<(), 判定の破れ> {
    形ごとの判定名(行, "遮蔽が生まれたことを示す最小符号値").上限を課す(行.gpuの性質.最小符号値, tolerance::遮蔽が出たと認める上限)
}

/// 中央行の底が肩より十分に濃いことを課す。段差と凹面で呼び名が違うだけであり、比べるものは同じである。
fn 底が肩より濃いことを検査する(行: &形の行, 底の呼び名: &str, 肩の呼び名: &str) -> Result<(), 判定の破れ> {
    let 性質 = &行.gpuの性質;
    let 見るもの = format!("{底の呼び名}{}が{肩の呼び名}{}より十分に濃いこと", 性質.中央行の底, 性質.中央行の肩);
    形ごとの判定名(行, &見るもの).真であることを課す(性質.中央行の底 + tolerance::底と肩の隔たりの下限 < 性質.中央行の肩)
}

/// どの形の行に課した判定かを名前が言う。4つの形を1つずつ通すため、形を書かないと破れた行を特定できない。
fn 形ごとの判定名(行: &形の行, 見るもの: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{}の{見るもの}", 行.形))
}
