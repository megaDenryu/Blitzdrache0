//! 局所可視度を0・中間・1へ固定した3枚のHDR画像から、項ごとの振る舞いを数で採る工程。
//! 受け取るのは3枚、返すのは実測値である。合否は`term_judgment`が決める。
//!
//! 採る数は4つである。局所可視度で動いた画素の数、明るいまま1ビットも動かなかった画素の数とその最大輝度、
//! 局所可視度を上げたのに暗くなった成分の数、そして中間の値での線形性の最大相対ずれである。
//!
//! 3つ目が数えるのは掛かる向きの裏返りである。局所可視度を上げることは遮蔽を弱めることであり、拡散間接照度は増えるか変わらないかのどちらかしか取らない。上げたのに減った成分が1つでもあれば、掛け算の向きが逆である。
//!
//! 明るいまま動かない画素が要るのは、動いた画素の数だけでは「掛かる先が拡散間接だけか」を決められないためである。
//! 直接光や鏡面間接にも掛けている実装では、それらを受けている画素も一緒に動く。金属の板は拡散の取り分が0で
//! 拡散間接照度を持たないため、掛かる先が正しければ1ビットも動かない。

use super::hdr_image::{HDR画像, 画素あたり成分数};

/// 明るい画素と認める相対輝度の下限。背景をクリア色ごと黒へ落としてあるため、この値を超える画素は
/// シーンの画素段が描いた画素だけである。
const 明るいと認める輝度: f32 = 0.01;
/// 成分の差が意味を持つと認める大きさ。半精度で記録した値の最下位の揺れをこの下限が切り分ける。
const 差が意味を持つ下限: f32 = 1.0e-4;

pub(super) struct 項別の実測 {
    pub(super) 画素数: usize,
    pub(super) 動いた画素数: usize,
    pub(super) 明るいまま不変の画素数: usize,
    pub(super) 不変の画素の最大輝度: f32,
    pub(super) 暗くなった成分数: usize,
    pub(super) 中間で外れた不変画素数: usize,
    pub(super) 線形性の最大相対ずれ: f32,
}

/// 前提: 3枚は同じ世界・同じ時刻・同じ寸法で撮ってあり、局所可視度の固定値だけが違う。
pub(super) fn 測る(遮蔽なし: &HDR画像, 中間: &HDR画像, 全遮蔽: &HDR画像, 中間の符号値: u8) -> Result<項別の実測, String> {
    if 遮蔽なし.画素数 != 中間.画素数 || 遮蔽なし.画素数 != 全遮蔽.画素数 {
        return Err("3枚のHDR画像の画素数が揃っていない".to_string());
    }
    let 比 = f32::from(中間の符号値) / f32::from(u8::MAX);
    let mut 実測 = 初期値(遮蔽なし.画素数);
    for 位置 in 0..遮蔽なし.画素数 {
        let 零 = 成分を取る(全遮蔽, 位置);
        let 中 = 成分を取る(中間, 位置);
        let 一 = 成分を取る(遮蔽なし, 位置);
        if 零 == 一 {
            不変の画素を数える(&mut 実測, 零, 中);
        } else {
            動いた画素を数える(&mut 実測, 零, 中, 一, 比);
        }
    }
    Ok(実測)
}

fn 初期値(画素数: usize) -> 項別の実測 {
    項別の実測 {
        画素数,
        動いた画素数: 0,
        明るいまま不変の画素数: 0,
        不変の画素の最大輝度: 0.0,
        暗くなった成分数: 0,
        中間で外れた不変画素数: 0,
        線形性の最大相対ずれ: 0.0,
    }
}

/// 局所可視度で動かなかった画素。明るければ直接光か鏡面間接を受けており、その項が不変である証拠になる。
/// 中間の値でだけ動いた画素は、掛け算が単調でないことを意味するため別に数える。
fn 不変の画素を数える(実測: &mut 項別の実測, 零: [f32; 3], 中: [f32; 3]) {
    let 輝度 = 相対輝度(零);
    if 輝度 > 明るいと認める輝度 {
        実測.明るいまま不変の画素数 += 1;
        実測.不変の画素の最大輝度 = 実測.不変の画素の最大輝度.max(輝度);
    }
    if 中 != 零 {
        実測.中間で外れた不変画素数 += 1;
    }
}

/// 局所可視度で動いた画素。可視度を上げたのに暗くなる成分があれば掛かる向きが逆であり、中間の値が両端の
/// 内分から外れれば掛け算が線形でない。
fn 動いた画素を数える(実測: &mut 項別の実測, 零: [f32; 3], 中: [f32; 3], 一: [f32; 3], 比: f32) {
    実測.動いた画素数 += 1;
    for 軸 in 0..3 {
        let 全幅 = 一[軸] - 零[軸];
        if 全幅 < 0.0 {
            実測.暗くなった成分数 += 1;
        }
        if 全幅.abs() > 差が意味を持つ下限 {
            let ずれ = ((中[軸] - 零[軸]) - 比 * 全幅).abs() / 全幅.abs();
            実測.線形性の最大相対ずれ = 実測.線形性の最大相対ずれ.max(ずれ);
        }
    }
}

fn 成分を取る(画像: &HDR画像, 位置: usize) -> [f32; 3] {
    let 先頭 = 位置 * 画素あたり成分数;
    [画像.成分列[先頭], 画像.成分列[先頭 + 1], 画像.成分列[先頭 + 2]]
}

/// Rec.709の相対輝度。明るい画素の判定にだけ使う。
fn 相対輝度([赤, 緑, 青]: [f32; 3]) -> f32 {
    0.2126 * 赤 + 0.7152 * 緑 + 0.0722 * 青
}
