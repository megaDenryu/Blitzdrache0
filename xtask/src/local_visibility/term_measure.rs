//! 局所可視度を0・中間・1へ固定した3枚の圧縮前のHDR画像から、項ごとの振る舞いを数で採る工程。
//! 受け取るのは3枚、返すのは実測値である。合否は`term_judgment`が決める。
//!
//! 採る数は4つである。局所可視度で動いた画素の数、明るいまま1ビットも動かなかった画素の数とその最大輝度、
//! 局所可視度を上げたのに暗くなった成分の数、そして中間の値での線形性の最大相対ずれである。
//!
//! 3つ目が数えるのは掛かる向きの裏返りである。局所可視度を上げることは遮蔽を弱めることであり、拡散間接照度は増えるか変わらないかのどちらかしか取らない。上げたのに減った成分が1つでもあれば、掛け算の向きが逆である。
//!
//! 明るいまま動かない画素が要るのは、動いた画素の数だけでは「掛かる先が拡散間接だけか」を決められないためである。
//! 直接光や鏡面間接にも掛けている実装では、それらを受けている画素も一緒に動く。金属の板は拡散の取り分が0で
//! 拡散間接照度を持たないため、掛かる先が正しければ1ビットも動かない。

use super::term_tally::{不変の画素を数える, 動いた画素を数える};
use crate::acceptance::{判定の名前, 判定の破れ, 圧縮前のHDR画像};

/// 3枚が同じ寸法で撮れていることを見る判定。寸法が違うと同じ番号の画素が3枚で別の場所を指す。
const 中間の寸法: 判定の名前 = 判定の名前::定数から生成する("中間の圧縮前のHDR画像の寸法");
const 全遮蔽の寸法: 判定の名前 = 判定の名前::定数から生成する("全遮蔽の圧縮前のHDR画像の寸法");

/// 明るい画素と認める相対輝度の下限。背景をクリア色ごと黒へ落としてあるため、この値を超える画素は
/// シーンの画素段が描いた画素だけである。
pub(super) const 明るいと認める輝度: f32 = 0.01;
/// 成分の差が意味を持つと認める大きさ。半精度で記録した値の最下位の揺れをこの下限が切り分ける。
pub(super) const 差が意味を持つ下限: f32 = 1.0e-4;

pub(super) struct 項別の実測 {
    pub(super) 画素数: usize,
    pub(super) 動いた画素数: usize,
    pub(super) 明るいまま不変の画素数: usize,
    pub(super) 不変の画素の最大輝度: f32,
    pub(super) 暗くなった成分数: usize,
    pub(super) 中間で外れた不変画素数: usize,
    pub(super) 線形性の最大相対ずれ: f32,
}

/// 前提: 3枚は同じ世界・同じ時刻・同じ寸法で撮ってあり、局所可視度の固定値だけが違う。
pub(super) fn 測る(
    遮蔽なし: &圧縮前のHDR画像,
    中間: &圧縮前のHDR画像,
    全遮蔽: &圧縮前のHDR画像,
    中間の符号値: u8,
) -> Result<項別の実測, 判定の破れ> {
    中間の寸法.綴りの一致を課す(&中間.寸法の綴り(), &遮蔽なし.寸法の綴り())?;
    全遮蔽の寸法.綴りの一致を課す(&全遮蔽.寸法の綴り(), &遮蔽なし.寸法の綴り())?;
    let 比 = f32::from(中間の符号値) / f32::from(u8::MAX);
    let mut 実測 = 初期値(遮蔽なし.画素数());
    for 番号 in 遮蔽なし.画素の番号一覧() {
        let 零 = 全遮蔽.番号の画素(番号);
        let 中 = 中間.番号の画素(番号);
        let 一 = 遮蔽なし.番号の画素(番号);
        if 零 == 一 {
            不変の画素を数える(&mut 実測, 零, 中);
        } else {
            動いた画素を数える(&mut 実測, 零, 中, 一, 比);
        }
    }
    Ok(実測)
}

fn 初期値(画素数: usize) -> 項別の実測 {
    項別の実測 {
        画素数,
        動いた画素数: 0,
        明るいまま不変の画素数: 0,
        不変の画素の最大輝度: 0.0,
        暗くなった成分数: 0,
        中間で外れた不変画素数: 0,
        線形性の最大相対ずれ: 0.0,
    }
}
