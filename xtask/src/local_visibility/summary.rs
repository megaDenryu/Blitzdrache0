//! 成功時に出す要約の組み立て。受け取るのは形ごとの行と項別の実測、返すのは1行の文字列である。
//!
//! 誤差と性質を要約へ出すのは、閾値を通ったことより実測の値のほうが次の判断の材料になるためである。
//! 閾値を下げてよいか、機材を替えたら誤差がどう動いたかは、この行の数からしか読めない。

use super::parse::形の行;
use super::term_measure::項別の実測;

pub(super) fn 要約を組む(行一覧: &[形の行], 項別: &項別の実測) -> String {
    let 形ごと: Vec<String> = 行一覧.iter().map(形1つを組む).collect();
    format!(
        "{} | 項別(局所可視度0と中間と1): 動いた画素{}/{} 明るいまま不変{}(最大輝度{:.3}) 上げて暗くなった成分{}件 線形性の最大相対ずれ{:.5}",
        形ごと.join(" | "),
        項別.動いた画素数,
        項別.画素数,
        項別.明るいまま不変の画素数,
        項別.不変の画素の最大輝度,
        項別.暗くなった成分数,
        項別.線形性の最大相対ずれ
    )
}

fn 形1つを組む(行: &形の行) -> String {
    format!(
        "{}: 最大絶対誤差{} 第95百分位の誤差{} 一致{}/{} 静止一致 最小符号値{} 幅{} 底{}肩{}縁{} 隣接差(横{} 縦{})",
        行.形,
        行.最大絶対誤差,
        行.第95百分位の誤差,
        行.一致画素数,
        行.画素数,
        行.gpuの性質.最小符号値,
        行.gpuの性質.符号値の幅,
        行.gpuの性質.中央行の底,
        行.gpuの性質.中央行の肩,
        行.gpuの性質.中央行の縁,
        行.gpuの性質.横の最大隣接差,
        行.gpuの性質.縦の最大隣接差
    )
}
