//! 画素1つぶんを実測へ積む数え方。触れるのは実測の集計だけであり、絵にも起動にも触れない。
//!
//! 動いた画素と動かなかった画素で数える中身が違うため、2つに分ける。動かなかった画素からは
//! 「明るいのに不変か」と「中間の値でだけ動いていないか」を、動いた画素からは「掛かる向き」と
//! 「掛け算の線形性」を採る。

use super::term_measure::{差が意味を持つ下限, 明るいと認める輝度, 項別の実測};

/// 局所可視度で動かなかった画素。明るければ直接光か鏡面間接を受けており、その項が不変である証拠になる。
/// 中間の値でだけ動いた画素は、掛け算が単調でないことを意味するため別に数える。
pub(super) fn 不変の画素を数える(実測: &mut 項別の実測, 零: [f32; 3], 中: [f32; 3]) {
    let 輝度 = 相対輝度(零);
    if 輝度 > 明るいと認める輝度 {
        実測.明るいまま不変の画素数 += 1;
        実測.不変の画素の最大輝度 = 実測.不変の画素の最大輝度.max(輝度);
    }
    if 中 != 零 {
        実測.中間で外れた不変画素数 += 1;
    }
}

/// 局所可視度で動いた画素。可視度を上げたのに暗くなる成分があれば掛かる向きが逆であり、中間の値が両端の
/// 内分から外れれば掛け算が線形でない。
pub(super) fn 動いた画素を数える(実測: &mut 項別の実測, 零: [f32; 3], 中: [f32; 3], 一: [f32; 3], 比: f32) {
    実測.動いた画素数 += 1;
    for 軸 in 0..3 {
        let 全幅 = 一[軸] - 零[軸];
        if 全幅 < 0.0 {
            実測.暗くなった成分数 += 1;
        }
        if 全幅.abs() > 差が意味を持つ下限 {
            let ずれ = ((中[軸] - 零[軸]) - 比 * 全幅).abs() / 全幅.abs();
            実測.線形性の最大相対ずれ = 実測.線形性の最大相対ずれ.max(ずれ);
        }
    }
}

/// Rec.709の相対輝度。明るい画素の判定にだけ使う。
fn 相対輝度([赤, 緑, 青]: [f32; 3]) -> f32 {
    0.2126 * 赤 + 0.7152 * 緑 + 0.0722 * 青
}
