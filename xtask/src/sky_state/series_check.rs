//! 同じ代表時刻の系列どうしを比べる判定。受け取るのは初回の行と比べる相手の行、返すのは合否である。
//! 決定性は世界時刻を含む完全一致で、日境界の循環は世界時刻だけが違う一致で見る。

use super::parse::{世界時刻の鍵, 状態行};
use crate::acceptance::{判定の名前, 判定の破れ};
use crate::report_line_key::報告の行の鍵;

/// 片方の行にしか無い鍵を文面へ出すときの語。
const 鍵が無いことの綴り: &str = "なし";

/// 世界時刻を含む全項目が綴りとして一致することを求める。値を丸めずに比べるため、表示桁での一致にすり替わらない。
pub(super) fn 完全一致か(初回: &状態行, 再導出: &状態行) -> Result<(), 判定の破れ> {
    二回の導出の判定名(初回).綴りの一致を課す(&再導出.項目の綴り(), &初回.項目の綴り())
}

/// 世界時刻だけが違い、残りの全項目が一致することを求める。世界時刻まで同じなら日をずらせていない。
pub(super) fn 循環しているか(初回: &状態行, 別の日: &状態行) -> Result<(), 判定の破れ> {
    let 世界時刻がずれたか = 初回.値(&世界時刻の鍵) != 別の日.値(&世界時刻の鍵);
    世界時刻の判定名(初回, 別の日).真であることを課す(世界時刻がずれたか)?;
    for (鍵, 値) in 初回.項目一覧() {
        if 鍵 == &世界時刻の鍵 {
            continue;
        }
        項目の判定名(初回, 別の日, 鍵).綴りの一致を課す(別の日.値(鍵).unwrap_or(鍵が無いことの綴り), 値)?;
    }
    Ok(())
}

fn 二回の導出の判定名(初回: &状態行) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("名前{}の2回の導出が並べた全項目", 初回.名前))
}

fn 世界時刻の判定名(初回: &状態行, 別の日: &状態行) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "名前{}の系列{}の世界時刻秒が初回と違うか(同じなら日をずらせていない)",
        初回.名前, 別の日.系列
    ))
}

fn 項目の判定名(初回: &状態行, 別の日: &状態行, 鍵: &報告の行の鍵) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("名前{}の系列{}の{鍵}", 初回.名前, 別の日.系列))
}
