//! 同じ代表時刻の系列どうしを比べる判定。受け取るのは初回の行と比べる相手の行、返すのは合否である。
//! 決定性は世界時刻を含む完全一致で、日境界の循環は世界時刻だけが違う一致で見る。

use super::parse::{世界時刻の鍵, 状態行};

/// 世界時刻を含む全項目が文字列として一致することを求める。値を丸めずに比べるため、表示桁での一致にすり替わらない。
pub(super) fn 完全一致か(初回: &状態行, 再導出: &状態行) -> Result<(), String> {
    if 初回.項目 != 再導出.項目 {
        return Err(format!("名前{}の2回の導出が一致しない", 初回.名前));
    }
    Ok(())
}

/// 世界時刻だけが違い、残りの全項目が一致することを求める。世界時刻まで同じなら日をずらせていない。
pub(super) fn 循環しているか(初回: &状態行, 別の日: &状態行) -> Result<(), String> {
    if 初回.値(世界時刻の鍵) == 別の日.値(世界時刻の鍵) {
        return Err(format!("名前{}の系列{}が初回と同じ世界時刻を指している", 初回.名前, 別の日.系列));
    }
    for (鍵, 値) in &初回.項目 {
        if 鍵 == 世界時刻の鍵 {
            continue;
        }
        if 別の日.値(鍵) != Some(値.as_str()) {
            return Err(format!(
                "名前{}の系列{}で{鍵}が初回と違う({値} と {})",
                初回.名前,
                別の日.系列,
                別の日.値(鍵).unwrap_or("なし")
            ));
        }
    }
    Ok(())
}
