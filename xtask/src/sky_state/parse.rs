//! 終了時報告から天空状態の行を拾い出す工程。受け取るのはアプリの終了時報告、返すのは代表時刻ごとの状態行の一覧である。
//! 1行ぶんの型と、その行から鍵で値を読む口は`row`が持つ。

mod row;

pub(super) use row::{世界時刻の鍵, 影の鍵, 方向の鍵一覧, 状態行, 高度の鍵};

use crate::acceptance::{判定の名前, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;

const 行の見出し: 報告の見出し = 報告の見出し::定数から生成する("天空状態行 ");
const 天空状態行: 判定の名前 = 判定の名前::定数から生成する("報告の天空状態行");

pub(super) fn 行一覧を取り出す(報告: &終了時報告) -> Result<Vec<状態行>, 検収エラー> {
    let mut 一覧 = Vec::new();
    for 行 in 報告.見出しで始まる行の一覧(&行の見出し) {
        let 本文 = 行の見出し.見出しに続く本文(行.原文()).to_string();
        一覧.push(状態行::取り込む(行, &本文)?);
    }
    if 一覧.is_empty() {
        return Err(天空状態行.あるはずのものが無い破れ().into());
    }
    Ok(一覧)
}

pub(super) fn 系列を取る<'行>(行一覧: &'行 [状態行], 名前: &str, 系列: &str) -> Result<&'行 状態行, 検収エラー> {
    行一覧
        .iter()
        .find(|行| 行.名前 == 名前 && 行.系列 == 系列)
        .ok_or_else(|| 系列の判定名(名前, 系列).あるはずのものが無い破れ().into())
}

fn 系列の判定名(名前: &str, 系列: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("代表時刻{名前}の系列{系列}の天空状態行"))
}
