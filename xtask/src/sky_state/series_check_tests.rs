//! 系列どうしの判定が空回りしないことの検査。一致する組で通り、値が1つでも違えば落ちることを固定する。

use super::parse::状態行;
use super::series_check::{完全一致か, 循環しているか};

fn 行を作る(系列: &str, 世界時刻秒: &str, 強度: &str) -> 状態行 {
    状態行 {
        系列: 系列.to_string(),
        名前: "正午".to_string(),
        項目: vec![
            ("世界時刻秒".to_string(), 世界時刻秒.to_string()),
            ("方向光強度".to_string(), 強度.to_string()),
        ],
    }
}

#[test]
fn 同じ項目なら完全一致と判定する() {
    let 初回 = 行を作る("初回", "43200", "3");
    let 再導出 = 行を作る("再導出", "43200", "3");
    assert!(完全一致か(&初回, &再導出).is_ok());
}

#[test]
fn 値が1つ違えば完全一致で落ちる() {
    let 初回 = 行を作る("初回", "43200", "3");
    let 再導出 = 行を作る("再導出", "43200", "3.0000001");
    assert!(完全一致か(&初回, &再導出).is_err());
}

#[test]
fn 世界時刻だけが違えば循環と判定する() {
    let 初回 = 行を作る("初回", "43200", "3");
    let 翌日 = 行を作る("翌日", "129600", "3");
    assert!(循環しているか(&初回, &翌日).is_ok());
}

#[test]
fn 世界時刻が同じなら循環で落ちる() {
    let 初回 = 行を作る("初回", "43200", "3");
    let 翌日 = 行を作る("翌日", "43200", "3");
    assert!(循環しているか(&初回, &翌日).is_err());
}

#[test]
fn 世界時刻以外が違えば循環で落ちる() {
    let 初回 = 行を作る("初回", "43200", "3");
    let 翌日 = 行を作る("翌日", "129600", "2.9");
    assert!(循環しているか(&初回, &翌日).is_err());
}
