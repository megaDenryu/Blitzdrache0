//! 系列どうしの判定が空回りしないことの検査。一致する組で通り、値が1つでも違えば落ちることを固定する。
//! 標本を報告の綴りから作るのは、判定が読む行がこの検収の読み取りを実際に通ったものであることを固定するためである。

#![allow(clippy::unwrap_used)]

use super::parse::{状態行, 行一覧を取り出す};
use super::series_check::{完全一致か, 循環しているか};
use crate::acceptance::{検収の実行名, 終了時報告};

const 標本の実行名: 検収の実行名 = 検収の実行名::定数から生成する("sky_state_series_check");

/// 系列・世界時刻秒・方向光強度の3つ組から2行ぶんの報告を組み、読み取りを通した状態行にする。
fn 二行を作る(初回: (&str, &str, &str), 相手: (&str, &str, &str)) -> Vec<状態行> {
    let 本文 = format!("{}{}", 一行の綴り(初回), 一行の綴り(相手));
    行一覧を取り出す(&終了時報告::取り込む(&標本の実行名, 本文, String::new())).unwrap()
}

fn 一行の綴り((系列, 世界時刻秒, 強度): (&str, &str, &str)) -> String {
    format!("天空状態行 系列={系列} 名前=正午 世界時刻秒={世界時刻秒} 方向光強度={強度}\n")
}

#[test]
fn 同じ項目なら完全一致と判定する() {
    let 行一覧 = 二行を作る(("初回", "43200", "3"), ("再導出", "43200", "3"));
    assert!(完全一致か(&行一覧[0], &行一覧[1]).is_ok());
}

#[test]
fn 値が1つ違えば完全一致で落ちる() {
    let 行一覧 = 二行を作る(("初回", "43200", "3"), ("再導出", "43200", "3.0000001"));
    assert!(完全一致か(&行一覧[0], &行一覧[1]).is_err());
}

#[test]
fn 世界時刻だけが違えば循環と判定する() {
    let 行一覧 = 二行を作る(("初回", "43200", "3"), ("翌日", "129600", "3"));
    assert!(循環しているか(&行一覧[0], &行一覧[1]).is_ok());
}

#[test]
fn 世界時刻が同じなら循環で落ちる() {
    let 行一覧 = 二行を作る(("初回", "43200", "3"), ("翌日", "43200", "3"));
    assert!(循環しているか(&行一覧[0], &行一覧[1]).is_err());
}

#[test]
fn 世界時刻以外が違えば循環で落ちる() {
    let 行一覧 = 二行を作る(("初回", "43200", "3"), ("翌日", "129600", "2.9"));
    assert!(循環しているか(&行一覧[0], &行一覧[1]).is_err());
}
