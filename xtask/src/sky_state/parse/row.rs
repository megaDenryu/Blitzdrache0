//! 天空状態の1行と、その行から値を読む口。担当するのは「報告の1行を系列と名前と鍵つきの項目の並びへ写し、
//! 鍵を名指して値を読む」ことであり、判定は1つも持たない。
//! 行の綴りは`crates/blitz_app/src/reports/sky_state/row.rs`の出力と一致させている。
//!
//! 項目の並びを行そのものと別に持つのは、決定性と日境界の循環の判定が鍵を1つも名指さず全項目を比べるためである。
//! 鍵を名指して読む口は行へ委ね、報告の書式が変わったときの破れを検収の共通語彙のまま返す。

use crate::acceptance::{判定の名前, 報告の行, 検収エラー};
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

pub(in crate::sky_state) const 系列の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("系列");
pub(in crate::sky_state) const 名前の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("名前");
pub(in crate::sky_state) const 世界時刻の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("世界時刻秒");
pub(in crate::sky_state) const 高度の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("太陽高度度");
pub(in crate::sky_state) const 影の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("影");
pub(in crate::sky_state) const 方向の鍵一覧: [報告の行の鍵; 3] = [
    報告の行の鍵::定数から生成する("太陽方向東"),
    報告の行の鍵::定数から生成する("太陽方向天頂"),
    報告の行の鍵::定数から生成する("太陽方向南"),
];

/// 鍵と値が等号で結ばれる形。この報告の行は全項目がこの形で並ぶ。
const 値の結ばれ方: 鍵に値が結ばれる形 = 鍵に値が結ばれる形::等号の後ろが値である;

pub(in crate::sky_state) struct 状態行 {
    行: 報告の行,
    pub(in crate::sky_state) 系列: String,
    pub(in crate::sky_state) 名前: String,
    /// 系列と名前を除く鍵と値の対。値は報告が出した綴りのままであり、丸めも並べ替えもしない。
    項目: Vec<(報告の行の鍵, String)>,
}

impl 状態行 {
    pub(in crate::sky_state) fn 取り込む(行: 報告の行, 見出しに続く本文: &str) -> Result<Self, 検収エラー> {
        let 項目 = 項目を切り出す(見出しに続く本文)?;
        Ok(Self {
            系列: 行.鍵に結ばれた綴り(&系列の鍵, 値の結ばれ方)?,
            名前: 行.鍵に結ばれた綴り(&名前の鍵, 値の結ばれ方)?,
            行,
            項目,
        })
    }

    /// 鍵に結ばれた値を実数として読む。行が鍵を持たないことと数として読めないことを別の枝で返す。
    pub(in crate::sky_state) fn 数値(&self, 鍵: &報告の行の鍵) -> Result<f64, 検収エラー> {
        self.行.鍵に結ばれた数(鍵, 値の結ばれ方)
    }

    /// 鍵に結ばれた値を綴りのまま読む。数でない値(影の有効性)がこの口を通る。
    pub(in crate::sky_state) fn 綴り(&self, 鍵: &報告の行の鍵) -> Result<String, 検収エラー> {
        self.行.鍵に結ばれた綴り(鍵, 値の結ばれ方)
    }

    /// 鍵に結ばれた値。無いことを失敗と読み替えず、無いことを返す。日境界の循環の判定が、
    /// 片方の行にしか無い鍵を「なし」として文面へ出すためにこの口を通る。
    pub(in crate::sky_state) fn 値(&self, 鍵: &報告の行の鍵) -> Option<&str> {
        self.項目.iter().find(|(項目名, _)| 項目名 == 鍵).map(|(_, 値)| 値.as_str())
    }

    pub(in crate::sky_state) fn 項目一覧(&self) -> &[(報告の行の鍵, String)] {
        &self.項目
    }

    /// 全項目を1つの綴りへ並べる。区切りに空白を使えるのは、鍵も値も空白で切った語であって空白を含まないためである。
    pub(in crate::sky_state) fn 項目の綴り(&self) -> String {
        self.項目.iter().map(|(鍵, 値)| format!("{鍵}={値}")).collect::<Vec<String>>().join(" ")
    }
}

/// 見出しに続く本文を鍵と値の対の並びへ切る。系列と名前は行の素性であって項目でないため、この並びから外す。
fn 項目を切り出す(本文: &str) -> Result<Vec<(報告の行の鍵, String)>, 検収エラー> {
    let mut 項目 = Vec::new();
    for 語 in 本文.split_whitespace() {
        let Some((鍵, 値)) = 語.split_once('=') else {
            return Err(等号の判定名(語).あるはずのものが無い破れ().into());
        };
        let 鍵 = 報告の行の鍵::組み立てた綴りから生成する(鍵.to_string());
        if 鍵 == 系列の鍵 || 鍵 == 名前の鍵 {
            continue;
        }
        項目.push((鍵, 値.to_string()));
    }
    Ok(項目)
}

fn 等号の判定名(語: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("天空状態行の項{語}の中の鍵と値を区切る等号"))
}
