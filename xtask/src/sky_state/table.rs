//! 検収の出力表。受け取るのは状態行の一覧、返すのは人が読む表の標準出力である。
//! 判定に使う値は報告の行が丸めずに持つため、この表は桁を揃えた読み物であって判定の根拠ではない。

use super::parse::{影の鍵, 状態行};
use crate::acceptance::検収エラー;
use crate::report_line_key::報告の行の鍵;

const 列見出し: [&str; 8] = [
    "代表時刻",
    "一日内秒",
    "太陽高度度",
    "方向光強度",
    "環境光強度",
    "露出補正段",
    "昼係数",
    "影",
];
const 数値列の鍵: [報告の行の鍵; 6] = [
    報告の行の鍵::定数から生成する("一日内秒"),
    報告の行の鍵::定数から生成する("太陽高度度"),
    報告の行の鍵::定数から生成する("方向光強度"),
    報告の行の鍵::定数から生成する("環境光強度"),
    報告の行の鍵::定数から生成する("露出補正段"),
    報告の行の鍵::定数から生成する("昼係数"),
];

pub(super) fn 表を出す(行一覧: &[状態行]) -> Result<(), 検収エラー> {
    println!("[xtask] 代表時刻の天空状態(初回の系列)");
    println!("  {}", 列見出し.map(|見出し| format!("{見出し:>12}")).join(" "));
    for 行 in 行一覧.iter().filter(|行| 行.系列 == "初回") {
        println!("  {}", 一行を整形する(行)?);
    }
    Ok(())
}

fn 一行を整形する(行: &状態行) -> Result<String, 検収エラー> {
    let mut 列一覧 = vec![format!("{:>12}", 行.名前)];
    for 鍵 in &数値列の鍵 {
        列一覧.push(format!("{:>12.4}", 行.数値(鍵)?));
    }
    列一覧.push(format!("{:>12}", 行.綴り(&影の鍵)?));
    Ok(列一覧.join(" "))
}
