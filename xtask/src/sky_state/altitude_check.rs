//! 太陽高度の並びに対する判定。受け取るのは全状態行、返すのは合否である。
//! 正午が全代表時刻の最大、真夜中が最小であることと、その2つが地平線をまたいでいることを見る。

use super::parse::{状態行, 系列を取る, 高度の鍵};

pub(super) fn 最大と最小か(行一覧: &[状態行]) -> Result<(), String> {
    let 正午 = 系列を取る(行一覧, "正午", "初回")?.数値(高度の鍵)?;
    let 真夜中 = 系列を取る(行一覧, "真夜中", "初回")?.数値(高度の鍵)?;
    for 行 in 行一覧 {
        let 高度 = 行.数値(高度の鍵)?;
        if 高度 > 正午 || 高度 < 真夜中 {
            return Err(format!("名前{}の高度{高度}が正午{正午}と真夜中{真夜中}の外にある", 行.名前));
        }
    }
    if 真夜中 >= 0.0 || 正午 <= 0.0 {
        return Err(format!("正午{正午}と真夜中{真夜中}が地平線をまたいでいない"));
    }
    Ok(())
}
