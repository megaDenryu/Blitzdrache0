//! 太陽高度の並びに対する判定。受け取るのは全状態行、返すのは合否である。
//! 正午が全代表時刻の最大、真夜中が最小であることと、その2つが地平線をまたいでいることを見る。
//!
//! 地平線をまたぐことを符号の正しさで課すのは、真夜中に求めるのが「零より小さい」であって「零以下」でないためである。
//! 真夜中の高度の符号を反転した値が正であることは、真夜中の太陽が地平線より下にあることと同じである。

use super::parse::{状態行, 系列を取る, 高度の鍵};
use crate::acceptance::{判定の名前, 検収エラー};

const 真夜中の高度の符号を反転した度: 判定の名前 = 判定の名前::定数から生成する(
    "真夜中の太陽高度の符号を反転した度(正でなければ真夜中の太陽が地平線より下に無く、正午との対で地平線をまたいでいない)",
);
const 正午の高度の度: 判定の名前 =
    判定の名前::定数から生成する("正午の太陽高度の度(正でなければ正午の太陽が地平線より上に無く、真夜中との対で地平線をまたいでいない)");

pub(super) fn 最大と最小か(行一覧: &[状態行]) -> Result<(), 検収エラー> {
    let 正午 = 系列を取る(行一覧, "正午", "初回")?.数値(&高度の鍵)?;
    let 真夜中 = 系列を取る(行一覧, "真夜中", "初回")?.数値(&高度の鍵)?;
    for 行 in 行一覧 {
        let 高度 = 行.数値(&高度の鍵)?;
        高度の判定名(行).許容の範囲を課す(高度, 真夜中, 正午)?;
    }
    真夜中の高度の符号を反転した度.正であることを課す(-真夜中)?;
    Ok(正午の高度の度.正であることを課す(正午)?)
}

fn 高度の判定名(行: &状態行) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "系列{}・名前{}の太陽高度度(範囲の下限は真夜中の高度、上限は正午の高度である)",
        行.系列, 行.名前
    ))
}
