//! 状態行の一覧に対する判定の取りまとめ。受け取るのは代表時刻ごとの状態行、返すのは合否である。
//! 判定は5つ: 同一時刻の2回の導出の完全一致、日境界の循環、太陽方向の単位長、全出力の有限値、正午の最大と真夜中の最小。
//! 各判定の中身は`row_check`(行ごと)、`series_check`(系列どうし)、`altitude_check`(高度)にある。

use super::parse::{状態行, 系列を取る};
use super::{altitude_check, row_check, series_check};

/// 検収が必ず含むことを求める代表時刻。
const 必須の代表時刻: [&str; 4] = ["真夜中", "夜明け", "正午", "夕方"];

pub(super) fn 全項目を検査する(行一覧: &[状態行]) -> Result<(), String> {
    代表時刻がそろっているか(行一覧)?;
    for 行 in 行一覧 {
        row_check::有限値か(行)?;
        row_check::単位長か(行)?;
    }
    for 名前 in 名前一覧(行一覧) {
        let 初回 = 系列を取る(行一覧, &名前, "初回")?;
        series_check::完全一致か(初回, 系列を取る(行一覧, &名前, "再導出")?)?;
        series_check::循環しているか(初回, 系列を取る(行一覧, &名前, "前日")?)?;
        series_check::循環しているか(初回, 系列を取る(行一覧, &名前, "翌日")?)?;
    }
    altitude_check::最大と最小か(行一覧)
}

fn 代表時刻がそろっているか(行一覧: &[状態行]) -> Result<(), String> {
    for 名前 in 必須の代表時刻 {
        if !行一覧.iter().any(|行| 行.名前 == 名前) {
            return Err(format!("代表時刻{名前}の行が無い"));
        }
    }
    Ok(())
}

/// 現れた順に代表時刻の名前を重複なく集める。並び順を保つのは、報告の順序のまま判定と表を出すためである。
fn 名前一覧(行一覧: &[状態行]) -> Vec<String> {
    let mut 一覧: Vec<String> = Vec::new();
    for 行 in 行一覧 {
        if !一覧.contains(&行.名前) {
            一覧.push(行.名前.clone());
        }
    }
    一覧
}
