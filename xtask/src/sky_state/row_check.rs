//! 状態行1件だけで閉じる判定。受け取るのは1行、返すのは合否である。全出力の有限値と太陽方向の単位長を見る。

use super::parse::{方向の鍵一覧, 状態行};
use crate::acceptance::{判定の名前, 判定の破れ, 検収エラー};
use crate::report_line_key::報告の行の鍵;

/// 太陽方向の長さ1からの許容ずれ。f32の三角関数と正規化の丸めがこの桁に収まる。
const 単位長の許容差: f64 = 1e-5;

/// 数として読める項目がすべて有限であることを求める。読めない項目(影の有効性のような語)は数の判定の対象外である。
pub(super) fn 有限値か(行: &状態行) -> Result<(), 判定の破れ> {
    for (鍵, 値) in 行.項目一覧() {
        let Ok(数) = 値.parse::<f64>() else {
            continue;
        };
        項目の判定名(行, 鍵, 値).有限であることを課す(数)?;
    }
    Ok(())
}

pub(super) fn 単位長か(行: &状態行) -> Result<(), 検収エラー> {
    let mut 長さ二乗 = 0.0;
    for 鍵 in &方向の鍵一覧 {
        let 成分 = 行.数値(鍵)?;
        長さ二乗 += 成分 * 成分;
    }
    Ok(単位長の判定名(行).上限を課す((長さ二乗.sqrt() - 1.0).abs(), 単位長の許容差)?)
}

fn 項目の判定名(行: &状態行, 鍵: &報告の行の鍵, 値: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("系列{}・名前{}の{鍵}({値})", 行.系列, 行.名前))
}

fn 単位長の判定名(行: &状態行) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("系列{}・名前{}の太陽方向の長さの1からのずれ", 行.系列, 行.名前))
}
