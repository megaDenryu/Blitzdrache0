//! 状態行1件だけで閉じる判定。受け取るのは1行、返すのは合否である。全出力の有限値と太陽方向の単位長を見る。

use super::parse::{方向の鍵一覧, 状態行};

/// 太陽方向の長さ1からの許容ずれ。f32の三角関数と正規化の丸めがこの桁に収まる。
const 単位長の許容差: f64 = 1e-5;

/// 数として読める項目がすべて有限であることを求める。読めない項目(影の有効性のような語)は数の判定の対象外である。
pub(super) fn 有限値か(行: &状態行) -> Result<(), String> {
    for (鍵, 値) in &行.項目 {
        let Ok(数) = 値.parse::<f64>() else {
            continue;
        };
        if !数.is_finite() {
            return Err(format!("系列{}・名前{}の{鍵}が有限でない({値})", 行.系列, 行.名前));
        }
    }
    Ok(())
}

pub(super) fn 単位長か(行: &状態行) -> Result<(), String> {
    let mut 長さ二乗 = 0.0;
    for 鍵 in 方向の鍵一覧 {
        let 成分 = 行.数値(鍵)?;
        長さ二乗 += 成分 * 成分;
    }
    let ずれ = (長さ二乗.sqrt() - 1.0).abs();
    if ずれ > 単位長の許容差 {
        return Err(format!("系列{}・名前{}の太陽方向の長さが1から{ずれ}ずれている", 行.系列, 行.名前));
    }
    Ok(())
}
