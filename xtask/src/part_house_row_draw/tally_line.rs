//! アセットコンパイラの標準出力から、家並みの勘定の1行を取り出す型。受け取るのは取り込んだ標準出力、
//! 返すのは軒数と部品の種類数と材質スロット数の総和とプリミティブ数の総和と据えた部品の個体数である。
//!
//! 5つを1つの型が持つのは、どれも同じ1行からしか読めず、読み落としを同じ場所で拒みたいためである。
//! 期待値を検収の側に定数で持たないのは、部品を1つ足したときに検収だけが無言で通らなくなるためである。
//!
//! 注意: 行の綴りは書き手(`crates/blitz_asset_compiler/src/house_row/tally.rs`)にも同じものがある。
//! 両側にあることは`cargo xtask conform`の綴りの契約の検査が守る。

use crate::acceptance::{判定の名前, 検収の実行名, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

/// 家並みの勘定の行を見分ける語。コンパイラは同じ見出しで始まる行を何本も出すため、この語で1本へ絞る。
const 家並みの行を見分ける語: &str = "部品の家並み: 建てた軒数=";

const 軒数の欄: &str = "建てた軒数=";
const 部品の種類数の欄: &str = "部品の種類数=";
const 材質スロット数の欄: &str = "材質スロット数の総和=";
const プリミティブ数の欄: &str = "プリミティブ数の総和=";
const 個体数の欄: &str = "据えた部品の個体数=";

/// 焼く工程が数えた家並みの勘定。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct 焼いた家並みの勘定 {
    pub(super) 軒数: u64,
    pub(super) 部品の種類数: u64,
    pub(super) 材質スロット数の総和: u64,
    pub(super) プリミティブ数の総和: u64,
    pub(super) 据えた部品の個体数: u64,
}

impl 焼いた家並みの勘定 {
    pub(super) fn 標準出力から読む(標準出力: String) -> Result<Self, 検収エラー> {
        let 報告 = 終了時報告::取り込む(&検収の実行名::定数から生成する("house_row_compile"), 標準出力, String::new());
        Ok(Self {
            軒数: 欄を読む(&報告, 軒数の欄)?,
            部品の種類数: 欄を読む(&報告, 部品の種類数の欄)?,
            材質スロット数の総和: 欄を読む(&報告, 材質スロット数の欄)?,
            プリミティブ数の総和: 欄を読む(&報告, プリミティブ数の欄)?,
            据えた部品の個体数: 欄を読む(&報告, 個体数の欄)?,
        })
    }
}

fn 欄を読む(報告: &終了時報告, 欄の綴り: &str) -> Result<u64, 検収エラー> {
    let 行一覧 = 報告.見出しで始まる行の一覧(&報告の見出し::定数から生成する("[compile_assets] "));
    let 判定名 = 判定の名前::組み立てた綴りから生成する(format!("アセットコンパイラの報告の家並みの行の{欄の綴り}"));
    let 行 = 行一覧
        .iter()
        .find(|行| 行.原文().contains(家並みの行を見分ける語))
        .ok_or_else(|| 判定名.あるはずのものが無い破れ())?;
    行.鍵に結ばれた数(
        &報告の行の鍵::組み立てた綴りから生成する(欄の綴り.to_string()),
        鍵に値が結ばれる形::この綴りに続く数字の並びが値である,
    )
}
