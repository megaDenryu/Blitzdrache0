//! 段4の実証の判定。受け取るのは規模ごとの実測、返すのは合否である。
//!
//! 判定は2段ある。1段目は規模1つの中で、焼いた側が数えた勘定と走らせた側が出した計数が噛み合うことを見る。
//! 2段目は10軒と100軒のあいだで、発行数と部品の種類数が同じであることと、個体数だけが増えることを見る。
//!
//! **2段目が段4の主張そのものである。** 1つの規模だけでは、発行数がたまたまその軒数と一致しているのか
//! 軒数に依らないのかを見分けられない。
//! 参照: `_doc/設計/部品カタログと接合点.md`「検収の形」段4の完了条件

use super::measurement::規模ごとの実測;
use crate::acceptance::{判定の名前, 判定の破れ};

/// この世界が持つ群でない描画対象の数。地面1つだけである。描画発行はプリミティブごとに1回であり、
/// 地面は1つの材質しか持たないため、地面が立てる発行も1回である。
const 地面の描画対象の数: u64 = 1;

pub(super) fn 規模1つを検査する(実測: &規模ごとの実測) -> Result<(), 判定の破れ> {
    let 呼び名 = 実測.規模.呼び名();
    crate::count_consistency::計数の整合を検査する(呼び名, &実測.計数)?;
    判定名(呼び名, "検証層の指摘").零件であることを課す(実測.計数.validation件数)?;
    判定名(呼び名, "材質スロット数の総和(描画発行が立つプリミティブの数と一致するはずである)")
        .一致を課す(実測.勘定.材質スロット数の総和, 実測.勘定.プリミティブ数の総和)?;
    判定名(呼び名, "群でない描画対象の数(地面1つだけのはずである)").一致を課す(実測.群でない描画対象の数(), 地面の描画対象の数)?;
    判定名(呼び名, "シーンパスの発行数(地面の1と部品ごとのプリミティブ数の総和の和になるはずである)")
        .一致を課す(実測.シーンパスの発行数(), 地面の描画対象の数 + 実測.勘定.プリミティブ数の総和)?;
    判定名(
        呼び名,
        "可視判定へ登録された個体の候補数(焼く工程が据えた部品の個体数と一致するはずである)",
    )
    .一致を課す(実測.群の個体の候補数(), 実測.勘定.据えた部品の個体数)
}

/// 10軒と100軒の突き合わせ。発行数と部品の種類数が軒数に依らず、個体数だけが増えることを見る。
pub(super) fn 規模どうしを突き合わせる(十軒: &規模ごとの実測, 百軒: &規模ごとの実測) -> Result<(), 判定の破れ> {
    let 呼び名 = "10軒と100軒の突き合わせ";
    判定名(呼び名, "軒数(宣言した10軒と100軒がそのまま焼かれるはずである)").一致を課す(十軒.勘定.軒数, 10)?;
    判定名(呼び名, "軒数(宣言した10軒と100軒がそのまま焼かれるはずである)").一致を課す(百軒.勘定.軒数, 100)?;
    判定名(呼び名, "部品の種類数(軒数を変えても同じはずである)").一致を課す(十軒.勘定.部品の種類数, 百軒.勘定.部品の種類数)?;
    判定名(呼び名, "材質スロット数の総和(軒数を変えても同じはずである)")
        .一致を課す(十軒.勘定.材質スロット数の総和, 百軒.勘定.材質スロット数の総和)?;
    判定名(呼び名, "シーンパスの発行数(軒数を10倍にしても同じはずである)").一致を課す(十軒.シーンパスの発行数(), 百軒.シーンパスの発行数())?;
    判定名(呼び名, "100軒の個体数(10軒より多いはずである。増えるのは配置列の長さだけである)")
        .下限を課す(百軒.群の個体の候補数(), 十軒.群の個体の候補数() + 1)
}

fn 判定名(呼び名: &str, 見るもの: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{呼び名}の{見るもの}"))
}
