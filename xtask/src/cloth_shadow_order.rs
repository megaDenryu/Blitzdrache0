//! OW5第4段の検収入口。束の中の描画対象の走査順を入れ替えても布の影が動かないことを画素で確かめる。
//!
//! 布のシャドウ描画が通常の描画対象と同じパイプラインを借りていた頃は、布の頂点へ走査順で最初の描画対象の
//! 個体変換が掛かっていた。そのため描画対象を並べ替えるだけで布の影が動いた。この検収はその依存が残っていれば
//! 落ちる(参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「描画段階資源の器と布専用シャドウ経路」)。
//!
//! `--object-count 2`は同じ板を別々の配置変換で左右へ並べ、`--reverse-draw-order`はその2つの並びだけを逆にする。
//! 比べるのは生の画像でなく布の影が覆う画素の集合である。布そのものの画素は自己衝突の非決定性で実行ごとに揺れるため、
//! 生の画像では走査順の差と実行ごとの揺れを分けられない。判定の中身は`judgment`、1条件ぶんの起動は`run`にある。

mod error;
mod judgment;
mod run;

use std::path::{Path, PathBuf};

use error::布の影の走査順非依存の検収エラー;

use crate::acceptance::{判定の名前, 描画検収の実行環境, 検収の1回の実行, 検収の実行名};
use std::process::ExitCode;

const 出力ディレクトリ: &str = "target/cloth_shadow_order";
const シェーダーコピー先: &str = "target/cloth_shadow_order_shaders";
/// 布の影が絵に出ていると認めるための下限画素数。実測は3万画素の桁であり、構図が崩れたときだけ下回る。
const 布影の下限画素数: usize = 1000;
/// 影の領域が一致していると認める差のうち、布の影の画素数に比例する分の割合の逆数。
/// 布の自己衝突は実行ごとにわずかに揺れ、影の輪郭が数画素動く。1/100は実測の揺れより十分大きく、
/// 走査順への依存が作る食い違い(領域の半分の桁)より十分小さい。
const 一致とみなす差の割合の逆数: usize = 100;

pub fn 布の影の走査順を確認する() -> ExitCode {
    match 検収する() {
        Ok(要約) => {
            println!("[xtask] cloth-shadow-order成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] cloth-shadow-order失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

const 布の影が覆う画素: 判定の名前 =
    判定の名前::定数から生成する("布の影が覆う画素(下回るなら走査順の入替を比べる対象が無く検収が成立しない)");

fn 検収する() -> Result<String, 布の影の走査順非依存の検収エラー> {
    if !crate::gen_source_assets::生成する() || !crate::compile_assets::既定を生成する() {
        return Err(布の影の走査順非依存の検収エラー::検証用アセットを生成できなかった);
    }
    let 実行環境 = run::実行環境を作る(PathBuf::from(出力ディレクトリ))?;
    let 入口 = crate::shader_copy::一時コピーを作る(Path::new(シェーダーコピー先))
        .map_err(布の影の走査順非依存の検収エラー::シェーダーの一時コピーを作れなかった)?;

    let 読込順1回目 = 描く(&実行環境, "load_order_1", &入口, run::条件::布あり読込順)?;
    let 読込順2回目 = 描く(&実行環境, "load_order_2", &入口, run::条件::布あり読込順)?;
    let 読込順の布なし = 描く(&実行環境, "load_order_no_cloth", &入口, run::条件::布なし読込順)?;
    let 逆順 = 描く(&実行環境, "reverse_order", &入口, run::条件::布あり逆順)?;
    let 逆順の布なし = 描く(&実行環境, "reverse_order_no_cloth", &入口, run::条件::布なし逆順)?;

    let 基準の影 = judgment::布影領域を求める(読込順1回目.画像(), 読込順の布なし.画像())?;
    let 再現の影 = judgment::布影領域を求める(読込順2回目.画像(), 読込順の布なし.画像())?;
    let 逆順の影 = judgment::布影領域を求める(逆順.画像(), 逆順の布なし.画像())?;
    布の影が覆う画素.下限を課す(基準の影.画素数(), 布影の下限画素数)?;
    // 許容差は実行ごとの揺れ(再現性の床)に画素数比例の余裕を足した値にする。床をそのまま足すのは、
    // 走査順の入替を比べる2枚が同一条件2回と同じだけ揺れうるためである。
    let 再現性の床 = 基準の影.差の画素数(&再現の影);
    let 許容差 = 再現性の床 + 基準の影.画素数() / 一致とみなす差の割合の逆数;
    let 走査順の差 = 基準の影.差の画素数(&逆順の影);
    走査順の入替で食い違った画素の判定名(再現性の床).上限を課す(走査順の差, 許容差)?;

    let 読込順png = 読込順1回目.書き出し先().目視用の絵へ変換する()?;
    let 逆順png = 逆順.書き出し先().目視用の絵へ変換する()?;
    Ok(format!(
        "布の影が覆う{}画素のうち、走査順の入替で食い違ったのは{走査順の差}画素(同一条件2回は{再現性の床}画素、許容{許容差}画素)、絵は{}と{}",
        基準の影.画素数(),
        読込順png.display(),
        逆順png.display()
    ))
}

fn 走査順の入替で食い違った画素の判定名(再現性の床: usize) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "走査順の入替で食い違った布の影の画素(同一条件2回の差は{再現性の床}画素であり、超えるなら布の影が描画対象の走査順に依存している)"
    ))
}

fn 描く(
    実行環境: &描画検収の実行環境,
    実行名の綴り: &str,
    シェーダー入口: &Path,
    条件: run::条件,
) -> Result<検収の1回の実行, 布の影の走査順非依存の検収エラー> {
    Ok(実行環境.描いて読み戻す(検収の実行名::生成する(実行名の綴り)?, &run::起動指定を組み立てる(条件, シェーダー入口))?)
}
