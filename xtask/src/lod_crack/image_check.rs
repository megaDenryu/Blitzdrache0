//! 固定斜め視点へ投影した共有辺の帯だけを走査し、番兵背景色が露出していないことを判定する。
//! 投影座標は`terrain_origin`の初期カメラと1280×720画面を前提とし、向きごとにラスタライズで所有される共有辺側の1画素帯へ固定する。

use super::cases::継ぎ目方向;
use crate::acceptance::{判定の名前, 判定の破れ, 画素の横位置, 画素の縦位置, 読み戻し画像};

const 背景RGB: [u8; 3] = [63, 75, 97];
const 帯半幅画素: f64 = 0.49;
const 東向き共有辺: [(f64, f64); 2] = [(639.0, 370.0), (639.0, 700.0)];
const 西向き共有辺: [(f64, f64); 2] = [(640.0, 370.0), (640.0, 700.0)];
const 北向き共有辺: [(f64, f64); 9] = 水平共有辺(2.0);
const 南向き共有辺: [(f64, f64); 9] = 水平共有辺(-1.0);

pub(super) struct 検査結果 {
    pub(super) roi画素数: u64,
}

/// 帯に1画素も入らない構図では、この判定が何も見ないまま合格する。
const 固定投影帯の画素: 判定の名前 = 判定の名前::定数から生成する("固定投影帯の画素");

pub(super) fn 継ぎ目を検査する(画像: &読み戻し画像, 方向: 継ぎ目方向) -> Result<検査結果, 判定の破れ> {
    let 線 = match 方向 {
        継ぎ目方向::東 => &東向き共有辺[..],
        継ぎ目方向::西 => &西向き共有辺[..],
        継ぎ目方向::北 => &北向き共有辺[..],
        継ぎ目方向::南 => &南向き共有辺[..],
    };
    let mut roi画素数 = 0_u64;
    let mut 背景画素数 = 0_u64;
    for y in 1..画像.高さ().画素数() - 1 {
        for x in 1..画像.幅().画素数() - 1 {
            let 点 = (実数へ写す(x), 実数へ写す(y));
            if 線.windows(2).any(|区間| 線分からの距離(点, 区間[0], 区間[1]) <= 帯半幅画素) {
                roi画素数 += 1;
                if 背景か(画像, x, y) {
                    背景画素数 += 1;
                }
            }
        }
    }
    if roi画素数 == 0 {
        return Err(固定投影帯の画素.あるはずのものが無い破れ());
    }
    番兵背景の露出画素の判定名(roi画素数).零件であることを課す(背景画素数)?;
    Ok(検査結果 { roi画素数 })
}

fn 番兵背景の露出画素の判定名(roi画素数: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("固定投影帯の{roi画素数}画素中の番兵背景の露出画素"))
}

/// 注意: 画面の幅も高さも4096を超えないため、収まらない位置は存在しない。
fn 実数へ写す(位置: usize) -> f64 {
    f64::from(u32::try_from(位置).unwrap_or(u32::MAX))
}

const fn 水平共有辺(y補正: f64) -> [(f64, f64); 9] {
    [
        (648.0, 363.0 + y補正),
        (692.0, 358.0 + y補正),
        (745.0, 352.0 + y補正),
        (798.0, 348.0 + y補正),
        (851.0, 346.0 + y補正),
        (905.0, 343.0 + y補正),
        (959.0, 339.0 + y補正),
        (1014.0, 336.0 + y補正),
        (1058.0, 336.0 + y補正),
    ]
}

fn 線分からの距離(点: (f64, f64), 始点: (f64, f64), 終点: (f64, f64)) -> f64 {
    let 線 = (終点.0 - 始点.0, 終点.1 - 始点.1);
    let 点差 = (点.0 - 始点.0, 点.1 - 始点.1);
    let 長さ二乗 = 線.0 * 線.0 + 線.1 * 線.1;
    let 比率 = ((点差.0 * 線.0 + 点差.1 * 線.1) / 長さ二乗).clamp(0.0, 1.0);
    (点差.0 - 線.0 * 比率).hypot(点差.1 - 線.1 * 比率)
}

fn 背景か(画像: &読み戻し画像, x: usize, y: usize) -> bool {
    画像.座標の画素(画素の横位置::生成する(x), 画素の縦位置::生成する(y)) == 背景RGB
}
