//! 四方向、段差0・1・最大、細粗入替と片側欠落を、画面内に収まる2本の共有辺で列挙する。

#[derive(Clone, Copy)]
pub(super) enum 継ぎ目方向 {
    東,
    西,
    北,
    南,
}

pub(super) struct 検査条件 {
    pub(super) 名前: String,
    pub(super) 一方: (i32, i32),
    pub(super) 他方: (i32, i32),
    pub(super) 一方段: u8,
    pub(super) 他方段: u8,
    pub(super) 欠落: Option<(i32, i32)>,
    pub(super) 継ぎ目方向: 継ぎ目方向,
}

struct 方向条件 {
    名前: &'static str,
    一方: (i32, i32),
    他方: (i32, i32),
    継ぎ目方向: 継ぎ目方向,
}

const 方向一覧: [方向条件; 4] = [
    方向条件 {
        名前: "east",
        一方: (-1, 0),
        他方: (0, 0),
        継ぎ目方向: 継ぎ目方向::東,
    },
    方向条件 {
        名前: "west",
        一方: (0, 0),
        他方: (-1, 0),
        継ぎ目方向: 継ぎ目方向::西,
    },
    方向条件 {
        名前: "north",
        一方: (0, 0),
        他方: (0, -1),
        継ぎ目方向: 継ぎ目方向::北,
    },
    方向条件 {
        名前: "south",
        一方: (0, -1),
        他方: (0, 0),
        継ぎ目方向: 継ぎ目方向::南,
    },
];
const 段差一覧: [u8; 3] = [0, 1, 4];

pub(super) fn 全条件() -> Vec<検査条件> {
    let mut 一覧 = Vec::with_capacity(32);
    for 方向 in 方向一覧 {
        for 段差 in 段差一覧 {
            for 入替 in [false, true] {
                let (一方段, 他方段) = if 入替 { (段差, 0) } else { (0, 段差) };
                一覧.push(検査条件 {
                    名前: format!("{}_diff{段差}_swap{}", 方向.名前, u8::from(入替)),
                    一方: 方向.一方,
                    他方: 方向.他方,
                    一方段,
                    他方段,
                    欠落: None,
                    継ぎ目方向: 方向.継ぎ目方向,
                });
            }
        }
        for 存在側段 in [0, 4] {
            一覧.push(検査条件 {
                名前: format!("{}_missing_level{存在側段}", 方向.名前),
                一方: 方向.一方,
                他方: 方向.他方,
                一方段: 存在側段,
                他方段: 0,
                欠落: Some(方向.他方),
                継ぎ目方向: 方向.継ぎ目方向,
            });
        }
    }
    一覧
}
