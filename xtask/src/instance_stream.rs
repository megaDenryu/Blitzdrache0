//! OW4第4段の検収入口。地形と植生が同居する25チャンク世界を本番のストリーミング経路で走らせ、
//! 束の追加と解除で植生の状態が生まれて消えることと、その変動が資源を動かさないことを確かめる。
//! 3つの実行を比べる。静止して先読みするだけの実行、境界を横断して戻る実行、それにカメラの往復を足した実行である。
//! 判定の中身は`judgment`、画素の分類は`pixel_check`、実行の起動は`run`にある。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「ストリーミング統合」

mod error;
mod judgment;
mod pixel_check;
mod run;

use error::植生ストリーミング統合の検収エラー;

use crate::acceptance::描画フレーム数;
use std::process::ExitCode;

use crate::verify::{検証の出力の置き場名, 検証の出力ルート};

const 出力ディレクトリ: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("instance_stream");
const シェーダーコピー先: 検証の出力の置き場名 = 検証の出力の置き場名::生成する("instance_stream_shaders");

/// 静止だけの実行のフレーム数。経路の静止先読み局面と同じ長さであり、この実行は一度も移動しない。
const 静止フレーム数: 描画フレーム数 = 描画フレーム数::生成する(120);

/// 往復を含む実行のフレーム数。静止先読み120、往復80、整定120の合計である。
/// 整定を120フレーム置くのは、解除の予約から実破棄までに進行中フレームぶんの遅れがあり、
/// さらに再読込の完了までディスクの応答を待つためである。
const 往復フレーム数: 描画フレーム数 = 描画フレーム数::生成する(320);

/// カメラを1フレームおきに前後させる距離。可視判定の結果を実際に変えるため、チャンク一辺100メートルを超える幅を取る。
/// 位置源が固定経路であるため、この移動は必要集合を変えない。
const カメラ往復の刻み: &str = "120";

/// 実行へ渡すRAMとVRAMの上限。`run`が同じ値を引数として渡し、ここは判定に使う。
const 上限バイト数: u64 = 16 * 1024 * 1024;

pub fn 地形植生ストリーミングを確認する() -> ExitCode {
    match 検収する() {
        Ok(要約) => {
            println!("[xtask] instance-stream成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] instance-stream失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

fn 検収する() -> Result<String, 植生ストリーミング統合の検収エラー> {
    if !crate::gen_source_assets::検証用ソースアセットを生成して成否を返す() || !crate::compile_assets::地形世界を既定で生成する()
    {
        return Err(植生ストリーミング統合の検収エラー::検証用アセットを生成できなかった);
    }
    let 実行環境 = run::実行環境を作る(検証の出力ルート::既定().名前が指す置き場(出力ディレクトリ))?;
    let シェーダー入口 = crate::shader_copy::一時コピーを作る(&検証の出力ルート::既定().名前が指す置き場(シェーダーコピー先))
        .map_err(植生ストリーミング統合の検収エラー::シェーダーの一時コピーを作れなかった)?;

    let 静止 = run::走らせる(&実行環境, "preload", &シェーダー入口, 静止フレーム数, &[])?;
    let 往復 = run::走らせる(&実行環境, "roundtrip", &シェーダー入口, 往復フレーム数, &[])?;
    let カメラ往復 = run::走らせる(
        &実行環境,
        "camera_probe",
        &シェーダー入口,
        往復フレーム数,
        &["--lod-probe-step", カメラ往復の刻み],
    )?;

    judgment::束が出入りすることを検査する(&往復, &静止)?;
    judgment::残留がないことを検査する(&往復, &静止)?;
    judgment::段が実際に変わることを検査する(&往復)?;
    judgment::可視の変動が資源を動かさないことを検査する(&往復, &カメラ往復)?;
    judgment::実行ごとの上限を検査する(&[&静止, &往復, &カメラ往復], 上限バイト数)?;
    let 植生画素数 = pixel_check::地形の外への逸脱がないことを検査する(&往復.画像, 往復.計数.シーン.可視数)?;

    Ok(format!(
        "読込{}件(静止だけなら{}件)、解除{}件、最大台帳{}件、最終台帳{}件、可視材料登録{}件、GPU確保{}で往復前後一致、段変更{}フレームで変更時読込0件、カメラ往復で可視数{}から{}へ変わっても読込と確保は不変、植生画素{}、RAM {} bytes / VRAM {} bytes、validation 0件",
        往復.要約.ディスク読込件数,
        静止.要約.ディスク読込件数,
        往復.要約.gpu解除件数,
        往復.要約.最大台帳登録数,
        往復.要約.最終台帳登録数,
        往復.計数.可視材料登録数,
        往復.計数.現在確保数,
        往復.要約.lod変更フレーム数,
        往復.計数.シーン.可視数,
        カメラ往復.計数.シーン.可視数,
        植生画素数,
        往復.要約.最大ramバイト数,
        往復.要約.最大vramバイト数,
    ))
}
