//! OW4第4段の検収入口。地形と植生が同居する25チャンク世界を本番のストリーミング経路で走らせ、
//! 束の追加と解除で植生の状態が生まれて消えることと、その変動が資源を動かさないことを確かめる。
//! 3つの実行を比べる。静止して先読みするだけの実行、境界を横断して戻る実行、それにカメラの往復を足した実行である。
//! 判定の中身は`judgment`、画素の分類は`pixel_check`、実行の起動は`run`にある。
//! 参照: `_doc/設計/植生インスタンスと物量計測.md`「ストリーミング統合」

mod judgment;
mod pixel_check;
mod run;

use std::path::{Path, PathBuf};
use std::process::ExitCode;

const 出力ディレクトリ: &str = "target/instance_stream";
const シェーダーコピー先: &str = "target/instance_stream_shaders";

/// 静止だけの実行のフレーム数。経路の静止先読み局面と同じ長さであり、この実行は一度も移動しない。
const 静止フレーム数: &str = "120";

/// 往復を含む実行のフレーム数。静止先読み120、往復80、整定120の合計である。
/// 整定を120フレーム置くのは、解除の予約から実破棄までにフレームインフライトぶんの遅れがあり、
/// さらに再読込の完了までディスクの応答を待つためである。
const 往復フレーム数: &str = "320";

/// カメラを1フレームおきに前後させる距離。可視判定の結果を実際に変えるため、チャンク一辺100メートルを超える幅を取る。
/// 位置源が固定経路であるため、この移動は必要集合を変えない。
const カメラ往復の刻み: &str = "120";

/// 実行へ渡すRAMとVRAMの上限。`run`が同じ値を引数として渡し、ここは判定に使う。
const 上限バイト数: u64 = 16 * 1024 * 1024;

pub fn 実行する() -> ExitCode {
    match 検収する() {
        Ok(要約) => {
            println!("[xtask] instance-stream成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] instance-stream失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

fn 検収する() -> Result<String, String> {
    if !crate::gen_source_assets::生成する() || !crate::compile_assets::地形世界を既定で生成する() {
        return Err("検証用アセットの生成に失敗した".to_string());
    }
    let 出力先 = PathBuf::from(出力ディレクトリ);
    std::fs::create_dir_all(&出力先).map_err(|誤り| format!("出力先を作れなかった: {誤り}"))?;
    let シェーダー入口 = crate::shader_copy::一時コピーを作る(Path::new(シェーダーコピー先))?;

    let 静止 = run::走らせる(&出力先, "preload", &シェーダー入口, 静止フレーム数, &[])?;
    let 往復 = run::走らせる(&出力先, "roundtrip", &シェーダー入口, 往復フレーム数, &[])?;
    let カメラ往復 = run::走らせる(
        &出力先,
        "camera_probe",
        &シェーダー入口,
        往復フレーム数,
        &["--lod-probe-step", カメラ往復の刻み],
    )?;

    judgment::束が出入りすることを検査する(&往復, &静止)?;
    judgment::残留がないことを検査する(&往復, &静止)?;
    judgment::段が実際に変わることを検査する(&往復)?;
    judgment::可視の変動が資源を動かさないことを検査する(&往復, &カメラ往復)?;
    judgment::実行ごとの上限を検査する(&[&静止, &往復, &カメラ往復], 上限バイト数)?;
    let 植生画素数 = pixel_check::地形の外への逸脱がないことを検査する(&往復.画像, 往復.計数.シーン.可視数)?;

    Ok(format!(
        "読込{}件(静止だけなら{}件)、解除{}件、最大台帳{}件、可視材料登録{}件、GPU確保{}で往復前後一致、段変更{}フレームで変更時読込0件、カメラ往復で可視数{}から{}へ変わっても読込と確保は不変、植生画素{}、RAM {} bytes / VRAM {} bytes、validation 0件",
        往復.要約.ディスク読込件数,
        静止.要約.ディスク読込件数,
        往復.要約.gpu解除件数,
        往復.要約.最大台帳登録数,
        往復.計数.可視材料登録数,
        往復.計数.現在確保数,
        往復.要約.lod変更フレーム数,
        往復.計数.シーン.可視数,
        カメラ往復.計数.シーン.可視数,
        植生画素数,
        往復.要約.最大ramバイト数,
        往復.要約.最大vramバイト数,
    ))
}
