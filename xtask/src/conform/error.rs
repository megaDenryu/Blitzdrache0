//! 規約検査そのものを実行できなかったことを表す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! 違反(検査が見つけた規約破り)とは別物である。違反は`違反`が表し、報告して終了コードへ写す。こちらは
//! 「検査の材料を読めなかった」「正本の宣言が消えていて突き合わせる相手がいない」という、判定に到達できなかった側である。
//! 宣言の消失を違反でなく破れとして扱うのは、消失を「一致した」と読み替えないためである。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。様式は`acceptance/error.rs`に倣う。
//!
//! どの検査が実行できなかったかを枝で持たないのは、どの枝も読もうとしたファイルと宣言を名指しており、
//! そのファイルがどの検査の材料かは台帳を見れば一意に決まるためである。検査の名前を重ねて持つと、
//! 検査を足すたびに2箇所へ書くことになる。

mod display;

use std::path::PathBuf;

use crate::file_scan::ファイル走査の破れ;

#[derive(Debug)]
pub enum 規約検査の破れ {
    検査対象のファイルを読めなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    検査対象のディレクトリを読めなかった {
        ディレクトリ: PathBuf,
        誤り: std::io::Error,
    }, // 依存の白リスト検査等、ディレクトリそのものを開く検査だけが持つ破れ
    検査対象のファイルを走査できなかった(ファイル走査の破れ),
    定数の宣言が無い {
        パス: &'static str,
        前置き: &'static str,
    }, // 突き合わせる定数の宣言が正本にも写しにも見つからない。台帳が指す宣言が消えたか改名された
    定数の値を数として読めない {
        パス: &'static str,
        前置き: &'static str,
        綴り: String,
        誤り: std::num::ParseFloatError,
    },
    束縛番号を読めない {
        パス: &'static str,
        前置き: &'static str,
    },
    束縛の属性が無い {
        パス: &'static str,
        変数名: &'static str,
    },
    見本の宣言が無い {
        パス: &'static str,
        宣言名: &'static str,
    },
    見本の宣言に等号が無い {
        パス: &'static str,
        宣言名: &'static str,
    },
    見本の宣言が閉じていない {
        パス: &'static str,
        宣言名: &'static str,
    },
    見本の宣言の値を数として読めない {
        パス: &'static str,
        宣言名: &'static str,
        綴り: String,
        誤り: std::num::ParseFloatError,
    },
    見本の宣言に値が1つも無い {
        パス: &'static str,
        宣言名: &'static str,
    },
}

impl std::error::Error for 規約検査の破れ {}

/// ファイルの走査の破れを規約検査の破れへ載せる境界。走査の側は自分が規約検査の一部であることを知らない。
impl From<ファイル走査の破れ> for 規約検査の破れ {
    fn from(破れ: ファイル走査の破れ) -> Self {
        Self::検査対象のファイルを走査できなかった(破れ)
    }
}

impl 規約検査の破れ {
    /// 走査で得たパスを読めなかったときの破れ。読み取りの呼び出しが各検査に散るため、組み立てをここへ1つ置く。
    pub(super) fn ファイルを読めなかった(パス: &std::path::Path, 誤り: std::io::Error) -> Self {
        Self::検査対象のファイルを読めなかった {
            パス: パス.to_path_buf(),
            誤り,
        }
    }
}
