use std::path::PathBuf;

use crate::type_metrics::{ファイル別の観測を集める, 型計測, 集計する};

use super::error::規約検査の破れ;
use super::violation::違反;
use amount::型の分量;

pub fn 全型の分量を台帳と照合する() -> Result<Vec<違反>, 規約検査の破れ> {
    let ファイル別観測 = ファイル別の観測を集める()?;
    Ok(照合する(&集計する(&ファイル別観測)))
}

fn 照合する(計測一覧: &[型計測]) -> Vec<違反> {
    let mut 違反一覧: Vec<違反> = 計測一覧.iter().flat_map(計測1件を照合する).collect();
    let 計測済みの型名: Vec<&str> = 計測一覧.iter().map(|計測| 計測.型名.as_str()).collect();
    違反一覧.extend(ledger::計測に現れない型名一覧(&計測済みの型名).into_iter().map(消えた型の違反));
    違反一覧
}

fn 計測1件を照合する(計測: &型計測) -> Vec<違反> {
    let 分量 = 型の分量::計測から生成する(計測);
    let パス = 報告するパス(計測);
    let Some(上限) = ledger::上限を引く(&計測.型名) else {
        if !分量.閾値を超えているか() {
            return Vec::new();
        }
        let 説明 = format!("型「{}」が閾値を超えたが台帳に無い: {}", 計測.型名, 分量.綴り());
        return vec![違反::ファイル単位(パス, 説明)];
    };
    分量
        .上限との食い違い(上限)
        .map(|説明| 違反::ファイル単位(パス, 説明))
        .into_iter()
        .collect()
}

/// 違反を直す先は型の定義である。定義行を走査範囲に見つけられない型だけ、台帳そのものを指す。
fn 報告するパス(計測: &型計測) -> PathBuf {
    match &計測.宣言 {
        Some(宣言) => 宣言.ファイル.clone(),
        None => PathBuf::from(ledger::台帳のパス()),
    }
}

fn 消えた型の違反(型名: &'static str) -> 違反 {
    違反::ファイル単位(
        PathBuf::from(ledger::台帳のパス()),
        format!("台帳に載っている型「{型名}」が計測に現れない(台帳から削除する)"),
    )
}
