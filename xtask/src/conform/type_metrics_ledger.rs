/// Graphiteの生成物から外す検査の名前。報告の行がこの名前で外した検査を名乗る。
const 生成物から外す検査: &str = "型ごとの分量の台帳";

pub fn 全型の分量を台帳と照合する() -> Result<検査の報告, 規約検査の破れ> {
    let 観測 = 生成物を除いた観測::走査対象から集める()?;
    let 違反一覧 = 照合する(&集計する(&観測.観測一覧));
    let 外した生成物 = 対象外にした生成物::生成する(生成物から外す検査, 観測.除いた生成物一覧);
    Ok(検査の報告::生成する(違反一覧, Vec::new()).対象外にした生成物を足す(外した生成物))
}

fn 照合する(計測: &走査範囲の型計測) -> Vec<違反> {
    let 台帳 = 台帳::全区画から組む();
    let mut 違反一覧: Vec<違反> = 計測.型ごとの計測一覧.iter().flat_map(|型1件の計測| 計測1件を照合する(&台帳, 型1件の計測)).collect();
    let 計測済みの所在: Vec<&型の所在> = 計測.型ごとの計測一覧.iter().map(|計測| &計測.所在).collect();
    違反一覧.extend(台帳.計測に現れない項目一覧(&計測済みの所在).into_iter().map(消えた型の違反));
    違反一覧.extend(計測.定義の候補を1つに絞れなかった実装ブロック一覧.iter().map(引き当てられなかった実装ブロックの違反));
    違反一覧
}

fn 計測1件を照合する(台帳: &台帳, 計測: &型計測) -> Vec<違反> {
    let 分量 = 型の分量::計測から生成する(計測);
    let パス = 計測.所在.定義ファイルのパス();
    let 台帳の上限 = 台帳.上限を参照する(&計測.所在);
    if let Some(説明) = 分量.宣言が1つに決まらない違反の説明(&計測.所在, 台帳の上限.is_some()) {
        return vec![違反::ファイル単位(パス, 説明)];
    }
    let Some(上限) = 台帳の上限 else {
        if !分量.閾値を超えているか() {
            return Vec::new();
        }
        let 説明 = format!("型「{}」が閾値を超えたが台帳に無い: {}", 計測.所在, 分量.文字列());
        return vec![違反::ファイル単位(パス, 説明)];
    };
    分量.上限との食い違い(上限).map(|説明| 違反::ファイル単位(パス, 説明)).into_iter().collect()
}

fn 消えた型の違反(上限: &型ごとの上限) -> 違反 {
    違反::ファイル単位(PathBuf::from(上限.登録されている表のファイル), format!("台帳に載っている型「{}」が計測に現れない(台帳から削除する)", 上限.所在))
}

/// 定義を1つに絞れなかったimplブロックは、どの型の計測にも入っていない。黙って対象から外すと、
/// そのimplブロックのメソッドが数えられないまま検査が通る。
fn 引き当てられなかった実装ブロックの違反(実装ブロック: &定義の候補が複数ある実装ブロック) -> 違反 {
    違反::ファイル単位(
        実装ブロック.ファイル.clone(),
        format!("implブロックの実装対象「{}」の定義を1つに絞れず計測へ入れられない: 候補は {}", 実装ブロック.型名, 実装ブロック.候補の文字列()),
    )
}
