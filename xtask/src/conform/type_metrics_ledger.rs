//! 型ごとの分量(impl分散ファイル数・フィールド数・メソッド総数)を台帳と照合する検査。
//! 受け取るのは無し、返すのは違反一覧か、計測を実行できなかった理由である。
//!
//! ファイル単位の100行検査は、1つの型のimplを複数ファイルへ散らせば通過する。散らしても親の
//! フィールドは1つも減らないため、行数だけを見る検査は責務の集中を止められない。ここは現状の値を
//! 上限として台帳へ登録し、増えたら落とす。減ったときも落として台帳の更新を強制する。
//! 台帳の1行が指す型は、定義ファイルの相対パスと型名の組で一意に決まる。
//! 見出しで認めたGraphiteの生成物は計測から外し、外した件数と名前を報告する(2026-09-26の親の判断。Issue #187)。この検査は手で書いた型への責務の集中を見るものであり、
//! 生成物が利用者の型へ足すimplは手で編集できず、その目的に当たらないためである。生成物は `include!` で取り込まれ物理と論理のモジュールが一致しないため、
//! 生成物の `super::型` を計測が物理のパスから解けず、同じ名前の別の型と重なって定義を1つに絞れない違反にもなる。
//! 参照: CLAUDE.md「機械的強制」の型ごとの分量の台帳。

