//! 部品で組んだ並びの勘定を出す行の欄の綴り。
//!
//! この行はアセットコンパイラが部品で組んだ並びを焼くたびに出し、段4の検収が「発行数が件数に依らない」ことの
//! 期待値として読む。期待値を検収の側へ定数で持たないため、この行が読めないと検収は何とも比べられない。
//! 綴りがずれると検収は欄を見つけられず、部品を1つ足した実行が緑で通る。
//!
//! 材質スロット数とプリミティブ数を別の欄にするのは、描画発行がプリミティブごとに立つ一方で、
//! 設計の主張が材質スロット数で書かれているためである。2つが食い違ったらどちらかの前提が崩れている。
//!
//! **行を見分ける語と欄の鍵を別の綴りとして登録する。** 2026-08-16に、見分ける語が鍵を含んだ形
//! (「部品で組んだ並び: 組み上げた件数=」)で登録されていたため、読む側が持つ鍵の綴りだけが古いまま残っても
//! 検査が通る穴があった。見分ける語の側が契約を満たし、鍵の側は台帳に登録が無かったためである。

