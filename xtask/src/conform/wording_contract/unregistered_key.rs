//! 台帳に載るファイルが持つ鍵の綴りが、すべて台帳へ登録されているかの検査。
//! 受け取るのは台帳の全綴りと対象のファイル、返すのは登録の無い鍵の違反一覧である。
//!
//! **親の検査だけでは片側しか守れない。** あちらは「登録した綴りが両側のファイルに在るか」を見るため、
//! 読む側が台帳を経由しない鍵を直に書いても、登録済みの別の綴りが同じファイルに在れば検査は通る。
//! 2026-08-16の実害がこれである。行を見分ける語が鍵を含んだ形で登録されていたため、読む側の鍵の綴りだけが
//! 古いまま残っても緑になり、破れは実機の検収まで出なかった。
//!
//! 鍵とは、値がその綴りに続いて書かれる語のことである。この規約では鍵は必ず`=`で終わるため、
//! `=`で終わる文字列リテラルを鍵と見なす。値を埋め込む書式(`{}`で終わる行の綴り)は鍵ではないため当たらない。

use std::path::{Path, PathBuf};

use super::super::error::規約検査の破れ;
use super::super::source_lexing;
use super::super::violation::違反;

/// 鍵と見なす綴りの終わりの字。
const 鍵の終わりの字: char = '=';

pub(super) fn 登録の無い鍵を探す(
    登録済みの綴り一覧: &[&str], 対象ファイル一覧: &[&str]
) -> Result<Vec<違反>, 規約検査の破れ> {
    let mut 違反一覧 = Vec::new();
    for パス in 対象ファイル一覧 {
        let 内容 = std::fs::read_to_string(Path::new(パス))
            .map_err(|誤り| 規約検査の破れ::ファイルを読めなかった(Path::new(パス), 誤り))?;
        for 鍵 in 鍵らしい綴りを集める(&内容) {
            if !登録済みの綴り一覧.contains(&鍵.as_str()) {
                違反一覧.push(違反::ファイル単位(
                    PathBuf::from(*パス),
                    format!("鍵の綴り「{鍵}」が綴りの契約の台帳に無い(鍵を台帳へ登録するか、出す側の綴りと揃える)"),
                ));
            }
        }
    }
    Ok(違反一覧)
}

fn 鍵らしい綴りを集める(内容: &str) -> Vec<String> {
    source_lexing::文字列リテラル一覧(内容)
        .iter()
        .map(|断片| 断片.中身.clone())
        .filter(|中身| 中身.ends_with(鍵の終わりの字))
        .collect()
}
