//! 綴りが文字列リテラルの中に在るかの判定の検査。台帳の中身でなく判定の規則だけを見る。

use super::文字列リテラルの中に現れるか;

#[test]
fn 二重引用符に挟まれた綴りを出現と認める() {
    let 原文 = "fn 出す(件数: u64) {\n    println!(\"validationエラー・警告合計件数: {件数}\");\n}";
    assert!(文字列リテラルの中に現れるか(原文, "validationエラー・警告合計件数:"));
}

#[test]
fn 複数のリテラルが並ぶ行でも見つける() {
    let 原文 = r#"    match 語 { Some("透過率代表" | "多重散乱代表") => 1, _ => 0 }"#;
    assert!(文字列リテラルの中に現れるか(原文, "多重散乱代表"));
}

#[test]
fn 引用符入りのコメントでの言及は出現と認めない() {
    let 原文 = "//! 行の綴りは \"validationエラー・警告合計件数:\" と一致させている\nlet 値 = 1;";
    assert!(!文字列リテラルの中に現れるか(原文, "validationエラー・警告合計件数:"));
}

#[test]
fn 引用符入りのブロックコメントでの言及も出現と認めない() {
    assert!(!文字列リテラルの中に現れるか(r#"/* 例: "多重散乱代表" */"#, "多重散乱代表"));
}

#[test]
fn 生文字列の中の綴りを出現と認める() {
    assert!(文字列リテラルの中に現れるか(
        r##"let 語 = r#"多重散乱代表"#;"##,
        "多重散乱代表"
    ));
}

#[test]
fn 逃がし記号の引用符で綴りを見失わない() {
    assert!(文字列リテラルの中に現れるか(
        r#"let 語 = "\"多重散乱代表\"";"#,
        "多重散乱代表"
    ));
}

#[test]
fn 綴りが無ければ出現でない() {
    assert!(!文字列リテラルの中に現れるか(
        r#"    println!("描画発行内訳:");"#,
        "材質切替:"
    ));
}
