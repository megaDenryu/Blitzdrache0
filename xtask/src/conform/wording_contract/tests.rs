//! 綴りが文字列リテラルの中に在るかの判定の検査。台帳の中身でなく判定の規則だけを見る。

use super::文字列リテラルの中に現れるか;

#[test]
fn 二重引用符に挟まれた綴りを出現と認める() {
    assert!(文字列リテラルの中に現れるか(
        r#"    println!("validationエラー・警告合計件数: {件数}");"#,
        "validationエラー・警告合計件数:"
    ));
}

#[test]
fn 複数のリテラルが並ぶ行でも見つける() {
    assert!(文字列リテラルの中に現れるか(
        r#"        Some("透過率代表" | "多重散乱代表") => {"#,
        "多重散乱代表"
    ));
}

#[test]
fn コメントでの言及は出現と認めない() {
    assert!(!文字列リテラルの中に現れるか(
        "/// 行の綴りはvalidationエラー・警告合計件数である。",
        "validationエラー・警告合計件数"
    ));
}

#[test]
fn 綴りが無い行は出現でない() {
    assert!(!文字列リテラルの中に現れるか(
        r#"    println!("描画発行内訳:");"#,
        "材質切替:"
    ));
}
