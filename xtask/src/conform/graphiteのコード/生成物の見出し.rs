//! 生成物の見出しとは、Graphiteの生成器が生成物の先頭の2行へ書く、手編集を禁じる文と生成元の案内のことである。
//! 受け取るのは原文、返すのは見出しが在るか・在るなら生成元として何を名乗るかである。
//!
//! 文言の正本はGraphiteのリポジトリの graphite-codegen の generated_source.rs が持ち、このリポジトリの外にある。
//! 動的グラフのschemaも静的グラフのschemaとinstanceも同じ1つの関数で見出しを書くため、見出しは1種類だけである。
//! 2行目の生成元は、パッケージのディレクトリからの相対パスと宣言の行番号を `:` でつないだ表記である。

/// 生成物の1行目。生成器が書く文言と一字一句同じである。
const 見出しの1行目: &str = "// このファイルは Graphite が生成したため手編集しないこと。";

/// 生成物の2行目の前置き。この後ろに生成元の表記が続く。
const 生成元の行の前置き: &str = "// 生成元: ";

/// 原文の先頭の2行から読んだ見出し。
#[derive(Debug, PartialEq, Eq)]
pub(super) enum 生成物の見出し {
    無い,
    生成元を名乗る(String), // パッケージのディレクトリからの相対パス。行番号は落とす
    生成元の行を読めない,
}

impl 生成物の見出し {
    pub(super) fn 原文から読む(原文: &str) -> Self {
        let mut 行一覧 = 原文.strip_prefix('\u{feff}').unwrap_or(原文).lines().map(str::trim_end);
        if 行一覧.next() != Some(見出しの1行目) {
            return Self::無い;
        }
        let Some(生成元の表記) = 行一覧.next().and_then(|行| 行.strip_prefix(生成元の行の前置き)) else {
            return Self::生成元の行を読めない;
        };
        match 生成元の表記.rsplit_once(':') {
            Some((パス, 行番号)) if !パス.is_empty() && 行番号.parse::<usize>().is_ok() => Self::生成元を名乗る(パス.to_string()),
            _ => Self::生成元の行を読めない,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::生成物の見出し;

    #[test]
    fn 生成器が書く見出しから生成元のパスを読む() {
        let 原文 = "// このファイルは Graphite が生成したため手編集しないこと。\n// 生成元: src/仮の経路網.rs:55\n// 再生成: 案内\n";
        assert_eq!(生成物の見出し::原文から読む(原文), 生成物の見出し::生成元を名乗る("src/仮の経路網.rs".to_string()));
    }

    #[test]
    fn 一行目が一字でも違えば見出しは無い() {
        assert_eq!(生成物の見出し::原文から読む("// このファイルは Graphite が生成した。\n// 生成元: src/a.rs:1\n"), 生成物の見出し::無い);
        assert_eq!(生成物の見出し::原文から読む("\n// このファイルは Graphite が生成したため手編集しないこと。\n"), 生成物の見出し::無い);
    }

    #[test]
    fn 二行目が生成元の形でなければ読めないと答える() {
        for 二行目 in ["", "// 生成元: src/a.rs", "// 生成元: :3", "// 生成元: src/a.rs:三"] {
            let 原文 = format!("// このファイルは Graphite が生成したため手編集しないこと。\n{二行目}\n");
            assert_eq!(生成物の見出し::原文から読む(&原文), 生成物の見出し::生成元の行を読めない, "二行目: {二行目}");
        }
    }

    #[test]
    fn 復帰改行の原文も同じに読む() {
        let 原文 = "// このファイルは Graphite が生成したため手編集しないこと。\r\n// 生成元: src/a.rs:2\r\n";
        assert_eq!(生成物の見出し::原文から読む(原文), 生成物の見出し::生成元を名乗る("src/a.rs".to_string()));
    }
}
