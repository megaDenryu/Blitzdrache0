//! Graphiteの生成物の一覧とは、走査した原文の一覧の中で、見出しと生成元の宣言が結び付いたためGraphiteの生成物と認めたファイルと、
//! 見出しを持ちながら結び付かなかったファイルを持つ値のことである。受け取るのはパスと原文の対の一覧である。
//!
//! 生成物と認める条件は3つである。先頭の2行が生成物の見出しであること。見出しが名乗る生成元のファイルが走査した一覧に在ること。
//! 生成元の原文の `generated = "..."` の項が、生成元の置き場から数えてこのファイルを指していること。
//! 生成元はパッケージのディレクトリからの相対で書かれているため、このファイルの祖先のディレクトリを1つずつ根として試す。
//! 3検査の工程・設計オントロジーの構文検査・設計関係の抽出が、それぞれ自分の読んだ原文の一覧からこの値を組み、同じ判定を共有する。

use std::path::{Component, Path, PathBuf};

use super::super::violation::違反;
use super::手書きの宣言::生成先の表記一覧;
use super::生成物の取り込み::波括弧の中の取り込み先;
use super::生成物の見出し::生成物の見出し;

pub struct Graphiteの生成物の一覧 {
    生成物一覧: Vec<PathBuf>,
    結び付かない見出し一覧: Vec<(PathBuf, 見出しが結び付かない理由)>,
}

/// 生成物の見出しを持ちながら、生成物と認めなかった理由。
#[derive(Debug, PartialEq, Eq)]
pub(super) enum 見出しが結び付かない理由 {
    生成元の行を読めない,
    生成元が見つからない { 生成元: String },
    生成元がこのファイルを生成先に宣言していない { 生成元: PathBuf },
}

impl Graphiteの生成物の一覧 {
    pub fn 原文一覧から見分ける(原文一覧: &[(PathBuf, String)]) -> Self {
        let mut 一覧 = Self {
            生成物一覧: Vec::new(),
            結び付かない見出し一覧: Vec::new(),
        };
        for (パス, 原文) in 原文一覧 {
            let 生成元 = match 生成物の見出し::原文から読む(原文) {
                生成物の見出し::無い => continue,
                生成物の見出し::生成元の行を読めない => {
                    一覧.結び付かない見出し一覧.push((パス.clone(), 見出しが結び付かない理由::生成元の行を読めない));
                    continue;
                }
                生成物の見出し::生成元を名乗る(生成元) => 生成元,
            };
            match 生成元を探す(原文一覧, パス, &生成元) {
                None => 一覧.結び付かない見出し一覧.push((パス.clone(), 見出しが結び付かない理由::生成元が見つからない { 生成元 })),
                Some((生成元のパス, 生成元の原文)) if 生成先に宣言しているか(生成元のパス, 生成元の原文, パス) => 一覧.生成物一覧.push(パス.clone()),
                Some((生成元のパス, _)) => 一覧
                    .結び付かない見出し一覧
                    .push((パス.clone(), 見出しが結び付かない理由::生成元がこのファイルを生成先に宣言していない { 生成元: 生成元のパス.clone() })),
            }
        }
        一覧
    }

    pub fn 生成物か(&self, パス: &Path) -> bool {
        self.生成物一覧.iter().any(|生成物| 斜線の表記へ揃える(生成物) == 斜線の表記へ揃える(パス))
    }

    pub fn 生成物一覧(&self) -> &[PathBuf] {
        &self.生成物一覧
    }

    /// `mod` の宣言の本体が生成物の取り込みであり、取り込む先がこの一覧の生成物なら、その生成物のパスを返す。
    pub fn 波括弧の中で取り込む生成物(&self, 宣言元: &Path, 原文: &str, 宣言の行番号: usize) -> Option<PathBuf> {
        let 表記 = 波括弧の中の取り込み先(原文, 宣言の行番号)?;
        let 取り込む先 = 置き場(宣言元).join(表記);
        self.生成物か(&取り込む先).then_some(取り込む先)
    }

    /// 見出しを持ちながら生成物と認めなかったファイルの違反。そのファイルには3検査を当てたうえで、見出しの偽装か生成元との食い違いとして報告する。
    pub fn 結び付かない見出しの違反一覧(&self) -> Vec<違反> {
        self.結び付かない見出し一覧.iter().map(|(パス, 理由)| 違反::ファイル単位(パス.clone(), 理由.説明())).collect()
    }
}

impl 見出しが結び付かない理由 {
    fn 説明(&self) -> String {
        let 理由 = match self {
            Self::生成元の行を読めない => "2行目が `// 生成元: <パス>:<行番号>` の形でない".to_string(),
            Self::生成元が見つからない { 生成元 } => format!("見出しが名乗る生成元 {生成元} がこのファイルの祖先のどのディレクトリの下にも無い"),
            Self::生成元がこのファイルを生成先に宣言していない { 生成元 } => format!("生成元 {} の generated の項がこのファイルを指していない", 生成元.display()),
        };
        format!("Graphiteの生成物の見出しを持つが生成元の宣言と結び付かない({理由})。生成物と認めず行数・宣言の説明の注釈・参照パスの実在の検査を当てる")
    }
}

// 生成元はパッケージのディレクトリからの相対で書かれている。このファイルの祖先を根として1つずつ試し、一覧に在る最初のものを採る。
fn 生成元を探す<'a>(原文一覧: &'a [(PathBuf, String)], 生成物: &Path, 生成元: &str) -> Option<(&'a PathBuf, &'a str)> {
    生成物.ancestors().skip(1).find_map(|根| {
        let 候補 = 斜線の表記へ揃える(&根.join(生成元));
        原文一覧.iter().find(|(パス, _)| 斜線の表記へ揃える(パス) == 候補).map(|(パス, 原文)| (パス, 原文.as_str()))
    })
}

fn 生成先に宣言しているか(生成元のパス: &Path, 生成元の原文: &str, 生成物: &Path) -> bool {
    let 生成物の表記 = 斜線の表記へ揃える(生成物);
    生成先の表記一覧(生成元の原文).iter().any(|表記| 斜線の表記へ揃える(&置き場(生成元のパス).join(表記)) == 生成物の表記)
}

fn 置き場(パス: &Path) -> &Path {
    パス.parent().unwrap_or_else(|| Path::new(""))
}

// 走査が返すパスの区切りは実行環境で変わり、宣言の表記は斜線で書かれる。`.` と `..` を解いて斜線でつないだ表記で比べる。
fn 斜線の表記へ揃える(パス: &Path) -> String {
    let mut 部品一覧: Vec<String> = Vec::new();
    for 部品 in パス.components() {
        match 部品 {
            Component::CurDir => {}
            Component::ParentDir => {
                部品一覧.pop();
            }
            _ => 部品一覧.push(部品.as_os_str().to_string_lossy().replace('\\', "/")),
        }
    }
    部品一覧.join("/")
}
