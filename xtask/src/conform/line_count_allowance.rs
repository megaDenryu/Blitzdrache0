//! 何行まで許すかの判定と、100行を超えることを許したファイルの台帳。受け取るのはパスと数えた行数、返すのは違反一覧である。
//!
//! 台帳へ載せてよいのは2つの区分だけである。未正当な分割を避けるために統合した結果超えたファイル(上限150行)と、
//! 完成物の形をそのまま写す宣言の並びが1つのデータを成すファイル(行数で切ると宣言の一覧性そのものが壊れるため上限を置かない)である。
//! どちらの区分かは、その行がどちらの一覧に載っているかが表す。例外は放置すると増える一方であるため、
//! 台帳に載っているのに100行以内へ収まったファイルを違反として報告し、台帳からの削除を強制する。
//! 参照: グローバルCLAUDE.md「1ファイル100行の原則と分割の質」の100行を超えてよいかの判定の条5・条6、CLAUDE.md「100行超過の再設計と台帳の現状」。

use std::path::Path;

use super::violation::違反;

pub const 上限行数: usize = 100;

/// 統合した結果の超過に置く上限。ここまで伸びたら統合の判断か型の責務のどちらかを疑う。
const 統合した結果の上限行数: usize = 150;

/// 台帳の1行。超過を許した理由は、台帳からの削除を強制する違反の文言がそのまま読み手へ返す。
struct 超過を許すファイル {
    パス: &'static str,
    超過を許した理由: &'static str,
}

/// 超過を許す区分1つ。その区分が許す行数の上限と、その区分で登録したファイルの一覧を持つ。
struct 超過を許す区分 {
    許す上限行数: Option<usize>, // 値なしは上限を置かないことを表す
    ファイル一覧: &'static [超過を許すファイル],
}

/// 注意: 未正当な分割を避けるために統合した結果100行を超えたファイルだけを載せる。上限は150行である。
const 統合した結果の一覧: [超過を許すファイル; 0] = [];

/// 注意: 完成物の形をそのまま写す宣言の並びが1つのデータを成すファイルだけを載せる。上限は置かない。
const 宣言的データリテラルの一覧: [超過を許すファイル; 1] = [超過を許すファイル {
    パス: "xtask/src/main.rs",
    超過を許した理由: "Rustがクレートの根の mod の宣言を1つのファイルへ集めることを要求するため、コマンドを足すたびに必ず超える。並びは宣言的なデータであり、分割すると一覧性そのものが壊れる",
}];

const 超過を許す区分一覧: [超過を許す区分; 2] = [
    超過を許す区分 {
        許す上限行数: Some(統合した結果の上限行数),
        ファイル一覧: &統合した結果の一覧,
    },
    超過を許す区分 {
        許す上限行数: None,
        ファイル一覧: &宣言的データリテラルの一覧,
    },
];

pub fn 行数超過か(行数: usize) -> bool {
    行数 > 上限行数
}

/// 走査で得るパスの区切り文字は実行環境で変わるため、斜線へ揃えてから台帳と照合する。
fn 台帳の表記へ揃える(パス: &Path) -> String {
    パス.to_string_lossy().replace('\\', "/")
}

/// 数えた行数を台帳と突き合わせる。台帳に無いファイルの上限は100行であり、載ったファイルの上限はその区分が決める。
pub fn 数えた行数を台帳と突き合わせる(パス: &Path, 行数: usize) -> Vec<違反> {
    let 表記 = 台帳の表記へ揃える(パス);
    for 区分 in &超過を許す区分一覧 {
        if let Some(許容) = 区分.ファイル一覧.iter().find(|許容| 許容.パス == 表記) {
            return 許容.行数を判定する(パス, 行数, 区分.許す上限行数);
        }
    }
    if 行数超過か(行数) {
        vec![違反::ファイル単位(パス.to_path_buf(), format!("コードの行が{行数}行"))]
    } else {
        Vec::new()
    }
}

impl 超過を許すファイル {
    /// 台帳に載ったファイルの判定。100行以内へ収まったら台帳からの削除を強制し、その区分の上限を超えたら違反にする。
    fn 行数を判定する(&self, パス: &Path, 行数: usize, 許す上限行数: Option<usize>) -> Vec<違反> {
        if !行数超過か(行数) {
            let 文言 = format!("超過を許す台帳に載っているのにコードの行が{行数}行で収まっている(台帳から削除する。載せた理由は「{}」)", self.超過を許した理由);
            return vec![違反::ファイル単位(パス.to_path_buf(), 文言)];
        }
        match 許す上限行数 {
            Some(上限) if 行数 > 上限 => vec![違反::ファイル単位(パス.to_path_buf(), format!("コードの行が{行数}行(その区分が許す上限は{上限}行)"))],
            Some(_) | None => Vec::new(),
        }
    }
}

