//! 正本と写しが同じ値を持つべき定数の突き合わせ。写しの多くはslangにあり、クレートの依存方針のために
//! 値を持ち直したxtask自身の定数と、クレート同士で同じ値を約束している定数も対象に含む。
//! 受け取るのは無し(対象の組は表が持つ)、返すのは値が食い違った組の違反一覧である。
//!
//! 正本と写しはコメントでしか結ばれておらず、片方だけを直した食い違いは走らせても絵に出ない。
//! とりわけ「CPUは型付きエラー、GPUは異常値」という同じ境界を両側が持つ定数は、値がずれると
//! 検出の境界そのものがずれるため、GPUとCPUの一致検査でも捉えられない。ここが機械的に見る。

mod table;

use std::path::{Path, PathBuf};

use super::error::規約検査の破れ;
use super::violation::違反;

pub fn 全定数を検査する() -> Result<Vec<違反>, 規約検査の破れ> {
    let mut 違反一覧 = Vec::new();
    for 組 in table::領域一覧.iter().copied().flatten() {
        let 正本 = 値を読む(組.正本パス, 組.正本の前置き)?;
        let 写し = 値を読む(組.写しパス, 組.写しの前置き)?;
        if 正本 != 写し {
            違反一覧.push(違反::ファイル単位(
                PathBuf::from(組.写しパス),
                format!(
                    "{}の写しが正本と食い違う(正本{正本}・写し{写し}・正本は{})",
                    組.写しの前置き.trim(),
                    組.正本パス
                ),
            ));
        }
    }
    Ok(違反一覧)
}

/// 前置きで始まる行を1本見つけ、そのセミコロンまでを数として読む。
/// 見つからない場合を違反でなく失敗として扱うのは、宣言の消失を「一致した」と読み替えないためである。
fn 値を読む(パス: &'static str, 前置き: &'static str) -> Result<f64, 規約検査の破れ> {
    let 内容 =
        std::fs::read_to_string(Path::new(パス)).map_err(|誤り| 規約検査の破れ::ファイルを読めなかった(Path::new(パス), 誤り))?;
    let 行 = 内容
        .lines()
        .find(|行| 行.trim_start().starts_with(前置き))
        .ok_or(規約検査の破れ::定数の宣言が無い { パス, 前置き })?;
    let 数値 = 行.trim_start().trim_start_matches(前置き).split(';').next().unwrap_or("").trim();
    数値を読む(数値).map_err(|誤り| 規約検査の破れ::定数の値を数として読めない {
        パス,
        前置き,
        綴り: 数値.to_string(),
        誤り,
    })
}

/// 数の綴りと、`1.0 / 60.0`のような2つの数の商を読む。商を許すのは、基本刻みのように分母で書くのが正本の自然な綴りである
/// 定数を、写しと突き合わせるために小数へ書き直させないためである。
fn 数値を読む(綴り: &str) -> Result<f64, std::num::ParseFloatError> {
    match 綴り.split_once('/') {
        Some((分子, 分母)) => Ok(分子.trim().parse::<f64>()? / 分母.trim().parse::<f64>()?),
        None => 綴り.parse::<f64>(),
    }
}
