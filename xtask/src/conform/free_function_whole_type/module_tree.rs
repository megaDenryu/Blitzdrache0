//! 型が定義されたファイルから、その型が根になるモジュールの木を決め、あるファイルがその木の中にあるかを答える型。
//!
//! 検査が見るのは「切り出した先が親の型を丸ごと受け取る」形であり、親とは、その関数のファイルを子孫に持つ
//! モジュールで定義された型のことである。同じクレートの離れたモジュールで定義された型を対等な引数として
//! 受け取る純粋な計算(交差の判定等)は、規約が自由関数を許す形そのものであるため、木の外として落とす。

use std::path::{Path, PathBuf};

/// 拡張子を除いた語幹で持つ。ファイル名らしい綴りの重複の検査に、この検査の内側の綴りを数えさせないためである。
const モジュールの根になる語幹一覧: [&str; 3] = ["mod", "lib", "main"];

pub struct モジュールの木 {
    定義ファイル: PathBuf,
    子孫のディレクトリ: PathBuf,
}

impl モジュールの木 {
    pub fn 定義ファイルから生成する(定義ファイル: &Path) -> Self {
        Self {
            定義ファイル: 定義ファイル.to_path_buf(),
            子孫のディレクトリ: 子孫のディレクトリを求める(定義ファイル),
        }
    }

    pub fn この木の中のファイルか(&self, パス: &Path) -> bool {
        パス == self.定義ファイル || パス.starts_with(&self.子孫のディレクトリ)
    }
}

/// `x/mod.rs`の子孫は`x/`配下であり、`x/y.rs`の子孫は`x/y/`配下である。Rustのモジュールの綴り方に従う。
fn 子孫のディレクトリを求める(定義ファイル: &Path) -> PathBuf {
    let 親 = 定義ファイル.parent().unwrap_or(Path::new("")).to_path_buf();
    let Some(語幹) = 定義ファイル.file_stem().and_then(|語幹| 語幹.to_str()) else {
        return 親;
    };
    if モジュールの根になる語幹一覧.contains(&語幹) {
        return 親;
    }
    親.join(語幹)
}
