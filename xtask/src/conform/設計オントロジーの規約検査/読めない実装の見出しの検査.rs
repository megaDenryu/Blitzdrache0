//! `クレート構文検査` の説明関数のうち、`impl` で始まる実装の見出しを読めない行を違反にするもの。触るのは `ソース一覧` と `違反一覧` だけである。
//! 設計解釈マーカーの実装の集め方・実装の置き場の警告・マーカーの実装の正規形の検査・設計関係の抽出の所有者の実装の探し方の4か所は、読めた実装の見出しだけを見る(`impl_header.rs` の `implの見出しを読む`)。
//! 読めない見出しを4か所がそれぞれ外したままにすると、その実装はどの検査にも現れずに通り続けるため、ここで1度だけ違反として報告する。4か所で別々に数えると同じ行を重ねて報告するため、報告はこの1か所にまとめる。
//! 行の頭が `impl` でも実装の見出しでない行(rustfmt が次の行へ折った戻り値の型の `impl Iterator<…>,`)は、別の項目の見出しの途中の型の表記であり、違反にしない。

use super::super::violation::違反;
use super::impl_header::{implの見出しを集める, 実装の見出しを集めた結果};
use super::syntax_checker::クレート構文検査;

impl クレート構文検査 {
    /// `impl` で始まる実装の見出しを、どれも本体を開く `{` まで集めて構文として読めること。
    pub fn すべての実装の見出しを読めること(mut self) -> Self {
        let mut 該当する違反一覧 = Vec::new();
        for (パス, 行一覧) in self.ソース一覧() {
            for 添字 in 0..行一覧.len() {
                if let Some(理由) = 実装の見出しを読めない理由(行一覧, 添字) {
                    let 説明 = format!("設計オントロジー: 実装の見出しを読めない({理由})。設計解釈マーカーの検査と設計関係の抽出がこの実装を対象にできないため、見出しを直す");
                    該当する違反一覧.push(違反::行単位(パス.clone(), 添字 + 1, 説明));
                }
            }
        }
        self.違反一覧.extend(該当する違反一覧);
        self
    }
}

// 開始の行が `impl` で始まる実装の見出しなのに読めないときの理由。`impl` で始まらない行と、実装の見出しでない行と、読めた見出しは無しである。
fn 実装の見出しを読めない理由(行一覧: &[String], 開始: usize) -> Option<&'static str> {
    match implの見出しを集める(行一覧, 開始)? {
        実装の見出しを集めた結果::実装の見出しでない => None,
        実装の見出しを集めた結果::型引数が閉じず本体を開く波括弧に届かない => Some("型引数が閉じず本体を開く `{` に届かない"),
        実装の見出しを集めた結果::本体を開く波括弧に届いた(見出し) => 見出し.構文を読む().is_none().then_some("本体を開く `{` まで集めた見出しを構文として読めない"),
    }
}
