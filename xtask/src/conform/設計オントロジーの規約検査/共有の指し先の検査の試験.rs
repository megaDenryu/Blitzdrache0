//! 共有の指し先の検査と、2つの基底の契約の排他の試験。`M不変データ` の型が `M共有される不変データ` を名乗る型を標準の表記の `Arc` で持つことだけが許され、
//! 共有を名乗らない型を指す `Arc`・標準でない修飾の `Arc`・共有を名乗る型を借りる `&`・`Rc`・`Weak` は違反になることと、`M共有される不変データ` を名乗る型自身に純粋データ規約が当たることと、
//! 同じ型が2つの基底の契約を同時に名乗ると違反になることを固定する。

use super::tests::{ソース, 全部の説明関数を連ねた違反の説明一覧};

const 共有される地図: &str = "pub struct 地図 {\n    つながり: Vec<u8>,\n}\nimpl M共有される不変データ for 地図 {}\n";

// 地図を1つのフィールドで持つ規則の定義。`型の表記` がフィールドの型である。
fn 地図を持つ規則(型の表記: &str) -> String {
    format!("{共有される地図}#[derive(Clone)]\npub struct 規則 {{\n    地図: {型の表記},\n}}\nimpl M不変データ for 規則 {{}}\nimpl M規則 for 規則 {{}}\n")
}

#[test]
fn 構文解析_共有される不変データを指すarcは修飾の有無に依らず違反にならない() {
    for 型の表記 in ["Arc<地図>", "std::sync::Arc<地図>"] {
        let 説明一覧 = 全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", &地図を持つ規則(型の表記))]);
        assert!(説明一覧.is_empty(), "{型の表記}: {説明一覧:?}");
    }
}

#[test]
fn 構文解析_共有される不変データを名乗らない型を指すarcは違反になる() {
    let 内容 = format!("{}pub struct 名簿 {{\n    人数: u8,\n}}\n", 地図を持つ規則("Arc<名簿>"));
    let 説明一覧 = 全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", &内容)]);
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains("M不変データ `規則` の定義の `Arc<名簿>` の中身 `名簿` が `M共有される不変データ` を名乗っていない"));
}

