//! 命令の組の検査の試験。`M命令の組` は `Mコマンド` を名乗る型だけをフィールドに並べた構造体でなければ違反になることと、
//! `M遷移が受け取る命令` を名乗る型は `Mコマンド` と `M命令の組` のちょうど1つを名乗ることと、`M命令の組` と `MParameter` を同時に名乗る型が違反になることを固定する。

use super::tests::{ソース, 全部の説明関数を連ねた違反の説明一覧};

const コマンド2つの定義: &str = "#[derive(Clone)]\npub enum 水平移動の操作 {\n    止まる,\n}\nimpl M不変データ for 水平移動の操作 {}\nimpl M遷移が受け取る命令 for 水平移動の操作 {}\nimpl Mコマンド for 水平移動の操作 {}\n#[derive(Clone)]\npub enum ジャンプの操作 {\n    ジャンプする,\n}\nimpl M不変データ for ジャンプの操作 {}\nimpl M遷移が受け取る命令 for ジャンプの操作 {}\nimpl Mコマンド for ジャンプの操作 {}\n";

fn 組を足した違反の説明一覧(組の定義: &str) -> Vec<String> {
    let 内容 = format!("{コマンド2つの定義}{組の定義}impl M不変データ for 胴体の命令 {{}}\nimpl M遷移が受け取る命令 for 胴体の命令 {{}}\nimpl M命令の組 for 胴体の命令 {{}}\n");
    全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", &内容)])
}

#[test]
fn 構文解析_コマンドだけをフィールドに並べた命令の組は違反にならない() {
    let 説明一覧 = 組を足した違反の説明一覧("#[derive(Clone)]\npub struct 胴体の命令 {\n    水平移動: 水平移動の操作,\n    pub(crate) ジャンプ: ジャンプの操作,\n}\n");
    assert!(説明一覧.is_empty(), "{説明一覧:?}");
}

// 反証: 可視性の前置きを決まった表記でしか落とさないと、`pub(in パス)` の中の `::` を名前と型の区切りと読み、正しい組を違反にする。
#[test]
fn 構文解析_パスで範囲を決めた可視性のフィールドを持つ命令の組は違反にならない() {
    let 説明一覧 = 組を足した違反の説明一覧("#[derive(Clone)]\npub struct 胴体の命令 {\n    pub(in crate::x) 水平移動: 水平移動の操作,\n    pub(super) ジャンプ: ジャンプの操作,\n}\n");
    assert!(説明一覧.is_empty(), "{説明一覧:?}");
}

// 反証: フィールドの型を確かめないと、コマンドでない値を混ぜた組が命令の全体として通り、公理が組を通してその値を消費したと数える。
#[test]
fn 構文解析_コマンドでない型をフィールドに持つ命令の組は違反になる() {
    let 説明一覧 = 組を足した違反の説明一覧("pub struct 倒し量;\n#[derive(Clone)]\npub struct 胴体の命令 {\n    水平移動: 水平移動の操作,\n    倒し量: 倒し量,\n}\n");
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains("M命令の組 `胴体の命令` のフィールド `倒し量` の型 `倒し量` が `Mコマンド` を名乗っていない"));
}

#[test]
fn 構文解析_包みに入れたコマンドをフィールドに持つ命令の組は違反になる() {
    let 説明一覧 = 組を足した違反の説明一覧("#[derive(Clone)]\npub struct 胴体の命令 {\n    水平移動: Vec<水平移動の操作>,\n}\n");
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains("のフィールド `水平移動` の型の表記 `Vec<水平移動の操作>` を1つの名前として読めない"));
}

#[test]
fn 構文解析_列挙の命令の組は違反になる() {
    let 説明一覧 = 組を足した違反の説明一覧("#[derive(Clone)]\npub enum 胴体の命令 {\n    動く(水平移動の操作),\n}\n");
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains("M命令の組 `胴体の命令` は struct 定義が必要です"));
}

#[test]
fn 構文解析_コマンドと命令の組を同時に名乗る型は違反になる() {
    let 内容 = format!("{コマンド2つの定義}impl M命令の組 for ジャンプの操作 {{}}\n");
    let 説明一覧 = 全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", &内容)]);
    assert!(説明一覧.iter().any(|説明| 説明.contains("M命令の組 `ジャンプの操作` は `Mコマンド` も名乗っている")), "{説明一覧:?}");
}

#[test]
fn 構文解析_コマンドと命令の組のどちらも名乗らない遷移が受け取る命令は違反になる() {
    let 内容 = "#[derive(Clone)]\npub enum 合図 {\n    鳴らす,\n}\nimpl M不変データ for 合図 {}\nimpl M遷移が受け取る命令 for 合図 {}\n";
    let 説明一覧 = 全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", 内容)]);
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains("M遷移が受け取る命令 `合図` は `Mコマンド` と `M命令の組` のどちらも名乗っていない"));
}

// 反証: 命令の組と必須入力の束の排他を検査しないと、コマンドだけを並べた構造体が両方を名乗り、遷移のコマンドの位置と遷移パラメータの位置のどちらへも入れられる。
#[test]
fn 構文解析_命令の組と必須入力の束を同時に名乗る型は違反になる() {
    let 説明一覧 = 組を足した違反の説明一覧("#[derive(Clone)]\npub struct 胴体の命令 {\n    水平移動: 水平移動の操作,\n}\nimpl MParameter for 胴体の命令 {}\n");
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains("MParameter `胴体の命令` は `M命令の組` も名乗っている"), "{説明一覧:?}");
}
