//! `クレート構文検査` の説明関数のうち、純粋データ規約の対象の型を持つクレートで、共有の指し先の名前(`Arc`・`Rc`・`Weak`)を標準ライブラリの外から持ち込むことを違反にするもの。
//! 共有の指し先の検査(`共有の指し先の検査.rs`)と設計関係の抽出器は、修飾の無い `Arc<型>` を標準の `Arc` と読む。`use crate::自前::Arc;` の後や、同じクレートに
//! `struct Arc<T>` を定義した後では、修飾の無い `Arc<地図>` は標準でない型を指すのに、2つの読み手は標準の `Arc` として受け取る。そのため、名前を持ち込む形そのものを違反にする。
//! 違反にする形は3つである。1つ目は、`Arc`・`Rc`・`Weak` の名前を標準の表記以外のパスから持ち込む `use`(別名で `Arc` などの名前を付ける `use` を含む)である。
//! `Arc` の標準の表記は設計関係の抽出器と同じ一覧(`blitz_design_verification::標準の共有の包みの表記か`)で判定し、`Rc` と `Weak` はこの検査だけが読むため、ここで一覧を持つ。
//! 2つ目は、読み切れない `use` 文(`;` に届かない文・展開しきれない群・マクロのメタ変数を含む文)のうち、`Arc`・`Rc`・`Weak` の名前を識別子として含むものである。読めない文を黙って通すと、その文が持ち込む名前を見逃すためである。
//! 3つ目は、`Arc`・`Rc`・`Weak` の名前で `struct`・`enum`・`union` を定義することである。同じ名前の `type` の別名は、共有の指し先の別名の検査が違反にする。
//! 保証範囲の外: 一括取り込み(`use crate::自前::*;`)が持ち込む名前、マクロが生やす定義と取り込み、純粋データ規約の対象の型を持たないクレートの中の取り込みと定義である。

