/// 標準ライブラリの外から持ち込んではならない共有の指し先の名前。
const 共有の指し先の名前一覧: [&str; 3] = ["Arc", "Rc", "Weak"];
/// `Rc` と `Weak` の標準の表記。`Arc` の表記は `標準の共有の包みの表記か` が持つ。
const 標準の参照数と弱い参照の表記一覧: [&str; 6] = ["std::rc::Rc", "alloc::rc::Rc", "std::rc::Weak", "std::sync::Weak", "alloc::rc::Weak", "alloc::sync::Weak"];
/// 名前の型を定義する予約語。`type` は共有の指し先の別名の検査が見る。
const 型を定義する予約語一覧: [&str; 3] = ["struct ", "enum ", "union "];

const 取り込みの説明: &str = "設計オントロジー: 純粋データ規約の対象の型を持つクレートでは、共有の指し先の名前(`Arc`・`Rc`・`Weak`)を標準の表記(`std::sync::Arc`・`alloc::sync::Arc`・`std::rc::Rc` 等)以外から `use` で持ち込まない。共有の指し先の検査と設計関係の抽出器は修飾の無い `Arc` を標準の `Arc` と読むため、持ち込んだ別の型を標準の `Arc` と取り違える";
const 読み切れない取り込みの説明: &str =
    "設計オントロジー: 共有の指し先の名前(`Arc`・`Rc`・`Weak`)を含む `use` 文を読み切れない(`;` に届かない・波括弧の群を展開しきれない・マクロのメタ変数を含む)。この文が標準の外から名前を持ち込むかを確かめられないため、1行に読める形へ書き直す";
const 定義の説明: &str =
    "設計オントロジー: 純粋データ規約の対象の型を持つクレートでは、共有の指し先の名前(`Arc`・`Rc`・`Weak`)で型を定義しない。共有の指し先の検査と設計関係の抽出器は修飾の無い `Arc` を標準の `Arc` と読むため、定義した別の型を標準の `Arc` と取り違える";

impl クレート構文検査 {
    /// 純粋データ規約の対象の型を持つクレートのどのファイルも、`Arc`・`Rc`・`Weak` の名前を標準の表記以外から持ち込まず、その名前で型を定義していないこと。
    pub fn 共有の指し先の名前を標準の外から持ち込んでいないこと(mut self) -> Self {
        let 対象のクレート一覧: HashSet<OsString> = self.純粋データ規約の対象一覧().iter().map(|型| クレート名(&型.パス).to_os_string()).collect();
        let 該当一覧: Vec<(PathBuf, usize, &str)> = self
            .ソース一覧()
            .iter()
            .filter(|(パス, _)| 対象のクレート一覧.contains(クレート名(パス)))
            .flat_map(|(パス, 行一覧)| 標準の外から名前を持ち込む行一覧(行一覧).into_iter().map(|(行番号, 説明)| (パス.clone(), 行番号, 説明)))
            .collect();
        for (パス, 行番号, 説明) in 該当一覧 {
            self.違反一覧.push(違反::行単位(パス, 行番号, 説明.to_string()));
        }
        self
    }
}

// 標準の外から名前を持ち込む取り込みと、名前の型の定義の行番号(1始まり)と説明。
fn 標準の外から名前を持ち込む行一覧(行一覧: &[String]) -> Vec<(usize, &'static str)> {
    let mut 該当 = Vec::new();
    for 文 in 書き出しの行付きの取り込みの文一覧(行一覧) {
        let 説明 = match &文.読み取り {
            取り込みの文の読み取り::読めた(項目一覧) => 項目一覧.iter().any(標準の外から名前を持ち込むか).then_some(取り込みの説明),
            取り込みの文の読み取り::読み切れない { 読めた範囲の表記 } => 共有の指し先の名前一覧.iter().any(|名前| !識別子として現れる位置一覧(読めた範囲の表記, 名前).is_empty()).then_some(読み切れない取り込みの説明),
        };
        if let Some(説明) = 説明 {
            該当.push((文.書き出しの行 + 1, 説明));
        }
    }
    for (添字, 行) in 行一覧.iter().enumerate() {
        if 共有の指し先の名前で型を定義するか(行) {
            該当.push((添字 + 1, 定義の説明));
        }
    }
    該当.sort_by_key(|(行番号, _)| *行番号);
    該当
}

// 取り込みの項目が持ち込む名前(別名があれば別名、無ければパスの最後の名前)が共有の指し先の名前であり、パスがその名前の標準の表記でないか。
fn 標準の外から名前を持ち込むか(項目: &取り込みの項目) -> bool {
    let 持ち込む名前 = 項目.別名.as_deref().unwrap_or(項目.元の名前());
    match 持ち込む名前 {
        "Arc" => !標準の共有の包みの表記か(&項目.パス),
        "Rc" | "Weak" => !(項目.元の名前() == 持ち込む名前 && 標準の参照数と弱い参照の表記一覧.contains(&項目.パス.as_str())),
        _ => false,
    }
}

// 行が、頭の属性と可視性を読み飛ばした後で `struct Arc`・`enum Rc`・`union Weak` のように共有の指し先の名前の型を定義するか。
fn 共有の指し先の名前で型を定義するか(行: &str) -> bool {
    let 残り = 属性と可視性を読み飛ばす(行.trim());
    型を定義する予約語一覧.iter().filter_map(|予約語| 残り.strip_prefix(予約語)).any(|後ろ| {
        let 後ろ = 後ろ.trim_start();
        let 名前 = 後ろ.split(|文字: char| !識別子の文字か(文字)).next().unwrap_or_default();
        共有の指し先の名前一覧.contains(&名前)
    })
}
