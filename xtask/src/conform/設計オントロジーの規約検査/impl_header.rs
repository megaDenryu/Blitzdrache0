//! `impl` の見出しを、型引数内の式ブロックと区別して本体を開く `{` まで読む。受け取るのはコードだけの行の一覧と書き出しの行、返すのは見出しの表記か、`impl` の見出しでないときの無しである。
//! 行の頭が `impl` でも、別の項目の見出しの途中の型の表記(rustfmt が折った戻り値の型の `impl Iterator<…>,`)は実装の見出しと認めない。
//! 本体を開く `{` までを複数の行にわたって集める読み方は、`trait` の見出しを読む上位トレイトの宣言の抽出も使う。rustfmt が `where` 句を次の行以降へ折るためである。

use super::declaration_brackets::{最上位で開いた括弧, 見出しの括弧の深さ};
use super::line_matching::implの予約語より後ろ;
use super::実装の見出しの読み方::実装の見出しの構文;

/// 実装の見出し。見出しの行の先頭から本体を開く `{` までを空白で繋いだ表記を読んだ構文を持つ。
/// 構文は見出しを集めたときに読み終えており、本体を開く `{` まで集めた見出しは必ず構文として読める。
pub struct 実装の見出し {
    構文: 実装の見出しの構文,
    占める行の数: usize,
}

impl 実装の見出し {
    /// 見出しの表記を、実装の種類と対象の型と型引数の名前へ分けて読んだ構文。
    pub const fn 構文(&self) -> &実装の見出しの構文 {
        &self.構文
    }

    /// 見出しが書き出しの行から本体を開く `{` の行までに占める行の数。rustfmt が見出しを折ったときは2以上になる。
    pub const fn 占める行の数(&self) -> usize {
        self.占める行の数
    }

    /// 見出しを手放し、構文だけを取り出す。
    pub fn 構文を取り出す(self) -> 実装の見出しの構文 {
        self.構文
    }
}

/// `impl` で始まる行から、本体を開く `{` までの見出しを集めた結果。
pub enum 実装の見出しを集めた結果 {
    本体を開く波括弧に届いた(実装の見出し),
    型引数が閉じず本体を開く波括弧に届かない,
    実装の見出しでない,
}

/// 開始の行が `impl`(前に同じ行の属性と `unsafe` があってもよい)で始まるなら、本体を開く `{` までの見出しを読む。
/// 見出しを集めた結果が本体を開く波括弧に届いたときだけ有り、届かないときと実装の見出しでないときは無い。届かない見出しは `読めない実装の見出しの検査.rs` が1か所で違反として報告するため、呼び出し側は無しを外してよい。
/// ただし外してよいのは、その検査が走査する範囲(`クレート構文検査::ソース一覧()`。`crates` の下の、`src` を含むパスの `.rs` ファイル)の中の行に限る。範囲の外の行を走査する呼び出し側は、読めない見出しを自分で報告しなければならない。
pub fn implの見出しを読む(行一覧: &[String], 開始: usize) -> Option<実装の見出し> {
    match implの見出しを集める(行一覧, 開始)? {
        実装の見出しを集めた結果::本体を開く波括弧に届いた(見出し) => Some(見出し),
        実装の見出しを集めた結果::型引数が閉じず本体を開く波括弧に届かない | 実装の見出しを集めた結果::実装の見出しでない => None,
    }
}

/// 開始の行が `impl` で始まるなら、本体を開く `{` まで見出しを集める。`impl` で始まらなければ無い。
/// 括弧を数えるのは `impl` の予約語より後ろからである。前置き(属性と `unsafe`)は `implの予約語より後ろ` が読み飛ばしを確かめており、本体を開く `{` を含まない。
/// 本体を開く `{` に届いた見出しは、予約語より後ろを `実装の見出しの構文` として読んで返すため、構文を読めない見出しは現れない。
/// 項目の区切りの `;` か、開いていない括弧を閉じる文字に本体の `{` より先に出会えば、その行は実装の見出しでない。rustfmt が長い戻り値の型を
/// `-> Result<` の次の行から `impl Iterator<Item = X> + 'a,` と折ったとき、その行の頭は `impl` だが、関数の見出しの途中の型の表記である。
/// 型引数が閉じないまま最後の行まで本体の `{` に届かないときは、予約語より後ろで、丸括弧と角括弧の外の `;` が最初の `{` より先にあれば実装の見出しでないとし、
/// 無ければ見出しを読めない実装の見出しとする。
pub fn implの見出しを集める(行一覧: &[String], 開始: usize) -> Option<実装の見出しを集めた結果> {
    let 開始の行 = 行一覧.get(開始)?;
    let implより後ろ = implの予約語より後ろ(開始の行)?;
    let 予約語より後ろの行一覧 = std::iter::once(implより後ろ).chain(行一覧[開始 + 1..].iter().map(String::as_str));
    let mut 括弧 = 見出しの括弧の深さ::default();
    let mut 後ろの表記 = String::new();
    for (読み終えた行の数, 行) in 予約語より後ろの行一覧.clone().enumerate() {
        for 文字 in 行.chars() {
            if 括弧.開いていない括弧を閉じるか(文字) || (文字 == ';' && 括弧.最上位か()) {
                return Some(実装の見出しを集めた結果::実装の見出しでない);
            }
            後ろの表記.push(文字);
            if 括弧.一文字読む(文字) == 最上位で開いた括弧::本体の波括弧 {
                let 構文 = 実装の見出しの構文::implの予約語より後ろから読む(&後ろの表記);
                let 見出し = 実装の見出し {
                    構文, 占める行の数: 読み終えた行の数 + 1
                };
                return Some(実装の見出しを集めた結果::本体を開く波括弧に届いた(見出し));
            }
        }
        後ろの表記.push(' ');
    }
    Some(if 最初の波括弧より前に項目の区切りがあるか(予約語より後ろの行一覧) {
        実装の見出しを集めた結果::実装の見出しでない
    } else {
        実装の見出しを集めた結果::型引数が閉じず本体を開く波括弧に届かない
    })
}

// 行の並びの最初の `{` より前に、丸括弧と角括弧の外の `;` があるか。型引数が閉じない見出しでは山括弧の深さが当てにならないため、丸括弧と角括弧だけを数える。
// 数え始めるのは、本体に届いた見出しを集めるときと同じく `impl` の予約語より後ろからである。前置きの属性の中の `{`(`#[属性{ a }]`)を本体の書き出しと取り違えないためである。
fn 最初の波括弧より前に項目の区切りがあるか<'a>(行一覧: impl Iterator<Item = &'a str>) -> bool {
    let mut 深さ = 0usize;
    for 文字 in 行一覧.flat_map(str::chars) {
        match 文字 {
            '(' | '[' => 深さ += 1,
            ')' | ']' => 深さ = 深さ.saturating_sub(1),
            '{' => return false,
            ';' if 深さ == 0 => return true,
            _ => {}
        }
    }
    false
}

/// 開始の行の頭から本体を開く `{` までを、行を空白で繋いで集める。型引数の定数式の波括弧(`境界<{ 1 }>`)は本体の波括弧と区別する。ファイルの最後まで `{` に届かなければ無い。
pub fn 本体を開く波括弧までの表記を集める(行一覧: &[String], 開始: usize) -> Option<String> {
    let mut 括弧 = 見出しの括弧の深さ::default();
    let mut 表記 = String::new();
    for 行 in 行一覧.iter().skip(開始) {
        for 文字 in 行.chars() {
            表記.push(文字);
            if 括弧.一文字読む(文字) == 最上位で開いた括弧::本体の波括弧 {
                return Some(表記);
            }
        }
        表記.push(' ');
    }
    None
}

