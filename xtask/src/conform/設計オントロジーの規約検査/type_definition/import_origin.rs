//! 型の定義の探索(`type_definition.rs`)が、`impl マーカー for 型` の型名をどのモジュールから取り込んでいるかを求める問い。受け取るのは型名と実装の見出しの行の字句位置と、コードだけの行の一覧とその行ごとの字句位置、
//! 返すのは取り込み元のモジュールパスか、取り込み元が複数あるか、取り込んでいないか、`as` の別名のため取り込み元を求められないかである。
//! 見る `use` は、実装の位置のモジュールの直下とマクロの呼び出しの中に書いたものである(実装が局所の位置にあれば、そのファイルの局所の `use` も見る)。マクロの呼び出しの中の `use` も候補にするのは、展開した後にその名前を持ち込みうるためである。`crate::` はクレート名に、`super::` は親に、`self::` は `use` を書いた位置のモジュールに置き換える。起点の予約語の無いパスは、最初の区切りが位置のモジュールの子として在れば相対に、無ければ外部クレートのパスとして読む(`module_path/在るモジュールの一覧.rs`)。
//! 型名を名乗る明示の取り込みの取り込み元が2つ以上あれば(cfg で切り替わる取り込み)、1つに決めず取り込み元が複数あると答える。ソースの並びで最後(または最初)の取り込みを採ると、別の取り込みが指す型を検査から落とすためである。

use super::super::module_path::enclosing_module::行の字句位置;
use super::super::module_path::モジュールパス;
use super::super::module_path::在るモジュールの一覧::在るモジュールの一覧;
use super::super::use_resolution::{取り込みの項目, 書き出しの行付きの取り込みの項目一覧};

/// `use` 行から取り込み元を求めた結果。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 取り込み元を求めた結果 {
    取り込んでいない,
    取り込んでいる { モジュールパス: モジュールパス },
    取り込み元が複数ある,
    別名のため取り込み元を求められない,
}

/// あるファイルの中で、実装の見出しに書いた型名がどこから来たかの問い。型名と、実装の見出しの行の頭の字句位置と、起点の予約語の無いパスの起点を決める在るモジュールの一覧の組である。
pub struct 取り込み元の問い<'a> {
    pub 型名: &'a str,
    pub 実装の位置: &'a 行の字句位置,
    pub 在るモジュール: &'a 在るモジュールの一覧,
}

impl 取り込み元の問い<'_> {
    /// 実装の位置のモジュールの直下に書いた `use` から、型名の取り込み元を求める。実装が関数の本体などの局所の位置にあれば、そのファイルの局所の `use` も見る(局所の `use` がその名前を隠しうるため)。
    /// 字句位置一覧は行一覧と同じ並びの、行ごとの字句位置である。
    pub fn 行一覧から取り込み元を求める(&self, 行一覧: &[String], 字句位置一覧: &[行の字句位置]) -> 取り込み元を求めた結果 {
        let mut 取り込み元一覧: Vec<モジュールパス> = Vec::new();
        for (位置, 項目) in self.見える取り込みの項目一覧(行一覧, 字句位置一覧) {
            if 項目.別名.as_deref() == Some(self.型名) {
                return 取り込み元を求めた結果::別名のため取り込み元を求められない;
            }
            let 取り込み元 = 位置.モジュール.書かれたパスを在るモジュールで絶対にする(&項目.パス, self.在るモジュール).親();
            if 項目.別名.is_none() && 項目.元の名前() == self.型名 && !取り込み元一覧.contains(&取り込み元) {
                取り込み元一覧.push(取り込み元);
            }
        }
        match 取り込み元一覧.as_slice() {
            [] => 取り込み元を求めた結果::取り込んでいない,
            [取り込み元] => 取り込み元を求めた結果::取り込んでいる {
                モジュールパス: 取り込み元.clone()
            },
            _ => 取り込み元を求めた結果::取り込み元が複数ある,
        }
    }

    /// 実装の位置から見える glob の取り込み(`use a::*;`・`pub use a::*;`)の取り込み元のモジュールの一覧。見る `use` は `行一覧から取り込み元を求める` と同じである。
    /// glob の取り込みは名前を挙げずに持ち込むため、名前を名乗る取り込みが無くても、その名前がここから来ていることがある。
    pub fn 見える一括取り込みの取り込み元一覧(&self, 行一覧: &[String], 字句位置一覧: &[行の字句位置]) -> Vec<モジュールパス> {
        let mut 取り込み元一覧: Vec<モジュールパス> = Vec::new();
        for (位置, 項目) in self.見える取り込みの項目一覧(行一覧, 字句位置一覧) {
            let 取り込み元 = 位置.モジュール.書かれたパスを在るモジュールで絶対にする(&項目.パス, self.在るモジュール).親();
            if 項目.別名.is_none() && 項目.元の名前() == "*" && !取り込み元一覧.contains(&取り込み元) {
                取り込み元一覧.push(取り込み元);
            }
        }
        取り込み元一覧
    }

    // 実装の位置から見える取り込みの項目と、その `use` を書き出した行の字句位置。実装の位置のモジュールの直下とマクロの呼び出しの中の `use` と、
    // 実装が局所の位置にあればそのファイルの局所の `use` である。
    fn 見える取り込みの項目一覧<'a>(&self, 行一覧: &[String], 字句位置一覧: &'a [行の字句位置]) -> Vec<(&'a 行の字句位置, 取り込みの項目)> {
        let 実装の位置 = self.実装の位置;
        書き出しの行付きの取り込みの項目一覧(行一覧)
            .into_iter()
            .filter_map(|在り処| Some((字句位置一覧.get(在り処.書き出しの行)?, 在り処.項目)))
            .filter(|(位置, _)| {
                if 位置.局所の位置か() {
                    実装の位置.局所の位置か()
                } else {
                    位置.モジュール == 実装の位置.モジュール
                }
            })
            .collect()
    }
}
