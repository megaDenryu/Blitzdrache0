//! 見える定義の無い名前の出どころ。書いた位置から見える定義が無いと分かった修飾の無い名前が、`use` で標準ライブラリから取り込んだ名前か、
//! 一括取り込み(`use a::*;`。取り込み元のモジュールの公開された名前を全部まとめて取り込むこと)が持ち込んだ名前か、取り込みの無いプレリュードのトレイトの名前かを見分ける。
//! 標準ライブラリのクレートの名前と、Rust の標準のプレリュードが修飾も取り込みも無しに見せるトレイトの名前は、子のモジュールと並ぶ `標準ライブラリの名前の表` が持つ。
//! 修飾で書いたとき(`std::fmt::Display`)と取り込んで書いたとき(`use std::fmt::Display;` の後の `Display`)で、同じ標準ライブラリの項目の扱いを揃えるためである。
//! この問いは、書いた位置から見える定義が無いと分かった後に問う(同じ名前の定義がこのクレートに在れば、プレリュードの名前はそれに隠される)。
//!
//! **一括取り込みが見える位置では、プレリュードの名前であることだけを理由に標準ライブラリと答えない。** 一括取り込みはプレリュードの名前を隠す名前を
//! 持ち込みうるためである(`use crate::変換::*;` が自作の `trait From` を持ち込む)。標準ライブラリの外の取り込み先ごとに、その名前が持ち込まれるかを
//! 子のモジュール `一括取り込み先の探索` で求める。1つでも先をたどれなければ(取り込み先がさらに一括取り込みを持つときなど)定義をたどれないと答えて欠落に数え、
//! 黙って標準ライブラリにしない。定義が1つだけ見つかればその定義と答える。どの取り込み先にもその名前が確かに無ければ、その一括取り込みからは来ないため、
//! 標準ライブラリの一括取り込みとプレリュードの名前から決める(見える一括取り込みが標準ライブラリのモジュールだけのときと同じである)。

use std::path::PathBuf;

use super::super::module_path::モジュールパス;
use super::import_origin::{取り込み元の問い, 取り込み元を求めた結果};
use super::一括取り込み先の探索::一括取り込み先で名前を探した答え;
use super::再公開の追跡::再公開をたどる探索;
use super::標準ライブラリの名前の表::{プレリュードのトレイトの名前か, 標準ライブラリのモジュールか};
use super::{型の在り処の問い, 定義の探索の材料, 探す定義の宣言の種類};

/// 書いた位置から見える定義が無い修飾の無い名前の出どころ。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 見える定義の無い名前の出どころ {
    標準ライブラリの項目である,
    一括取り込みの先に定義がある { パス: PathBuf }, // 定義を書いたファイルのパス
    たどれない,
}

impl 型の在り処の問い<'_> {
    /// 修飾の無い問いの名前の出どころを、書いた位置の `use` から求める。書いた位置から見える定義が無いと分かった後に問う。
    pub(super) fn 見える定義の無い名前の出どころを求める(&self, 宣言: 探す定義の宣言の種類, 材料: &定義の探索の材料) -> 見える定義の無い名前の出どころ {
        let Some(ファイル) = 材料.ファイルを探す(self.参照元のパス) else {
            return 見える定義の無い名前の出どころ::たどれない;
        };
        let Some(位置) = ファイル.字句位置一覧.get(self.参照元の行番号.saturating_sub(1)) else {
            return 見える定義の無い名前の出どころ::たどれない;
        };
        let 問い = 取り込み元の問い {
            型名: self.型名,
            実装の位置: 位置,
            在るモジュール: 材料.在るモジュール(),
        };
        match 問い.行一覧から取り込み元を求める(ファイル.行一覧, ファイル.字句位置一覧) {
            取り込み元を求めた結果::取り込んでいる { モジュールパス: 取り込み元 } if 標準ライブラリのモジュールか(&取り込み元) => {
                見える定義の無い名前の出どころ::標準ライブラリの項目である
            }
            取り込み元を求めた結果::取り込んでいない => {
                self.一括取り込みの取り込み先かプレリュードから出どころを求める(宣言, 材料, 問い.見える一括取り込みの取り込み元一覧(ファイル.行一覧, ファイル.字句位置一覧))
            }
            取り込み元を求めた結果::取り込んでいる { .. } | 取り込み元を求めた結果::取り込み元が複数ある | 取り込み元を求めた結果::別名のため取り込み元を求められない => {
                見える定義の無い名前の出どころ::たどれない
            }
        }
    }

    // 名前を名乗る取り込みが無い名前の出どころを、見える一括取り込みの取り込み先とプレリュードから求める。標準ライブラリの外の取り込み先ごとに答えを求め、
    // 1つでも先をたどれなければたどれない、どれも確かに無ければ標準ライブラリの一括取り込みとプレリュードで決め、定義が1つだけ見つかればそれを答える。
    fn 一括取り込みの取り込み先かプレリュードから出どころを求める(
        &self,
        宣言: 探す定義の宣言の種類,
        材料: &定義の探索の材料,
        一括取り込みの取り込み元一覧: Vec<モジュールパス>,
    ) -> 見える定義の無い名前の出どころ {
        let (標準の一覧, 標準の外の一覧): (Vec<モジュールパス>, Vec<モジュールパス>) = 一括取り込みの取り込み元一覧.into_iter().partition(標準ライブラリのモジュールか);
        let 探索 = 再公開をたどる探索 { 材料, 型名: self.型名, 宣言 };
        let 答え一覧: Vec<一括取り込み先で名前を探した答え> = 標準の外の一覧.iter().map(|モジュール| 探索.一括取り込み先で名前を探す(モジュール)).collect();
        if 答え一覧.contains(&一括取り込み先で名前を探した答え::先をたどれない) {
            return 見える定義の無い名前の出どころ::たどれない;
        }
        let 見つかった一覧: Vec<PathBuf> = 答え一覧
            .iter()
            .filter_map(|答え| {
                if let 一括取り込み先で名前を探した答え::定義がある { パス } = 答え {
                    Some(パス.clone())
                } else {
                    None
                }
            })
            .collect();
        let 標準から持ち込む = !標準の一覧.is_empty() || 答え一覧.contains(&一括取り込み先で名前を探した答え::標準ライブラリから名前を取り込んでいる);
        match (見つかった一覧.as_slice(), 標準から持ち込む) {
            ([パス], false) => 見える定義の無い名前の出どころ::一括取り込みの先に定義がある { パス: パス.clone() },
            ([], true) => 見える定義の無い名前の出どころ::標準ライブラリの項目である,
            ([], false) if 宣言 == 探す定義の宣言の種類::トレイト && プレリュードのトレイトの名前か(self.型名) => 見える定義の無い名前の出どころ::標準ライブラリの項目である,
            _ => 見える定義の無い名前の出どころ::たどれない,
        }
    }
}
