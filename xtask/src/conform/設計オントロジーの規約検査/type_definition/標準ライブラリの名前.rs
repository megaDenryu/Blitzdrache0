//! 見える定義の無い名前の出どころ。書いた位置から見える定義が無いと分かった修飾の無い名前が、`use` で標準ライブラリから取り込んだ名前か、
//! glob の取り込み(`use a::*;`)が持ち込んだ名前か、取り込みの無いプレリュードのトレイトの名前かを見分ける。標準ライブラリのクレートの名前と、
//! Rust の標準のプレリュードが修飾も取り込みも無しに見せるトレイトの名前もここが持つ。
//! 修飾で書いたとき(`std::fmt::Display`)と取り込んで書いたとき(`use std::fmt::Display;` の後の `Display`)で、同じ標準ライブラリの項目の扱いを揃えるためである。
//! この問いは、書いた位置から見える定義が無いと分かった後に問う(同じ名前の定義がこのクレートに在れば、プレリュードの名前はそれに隠される)。
//!
//! **glob の取り込みが見える位置では、プレリュードの名前であることだけを理由に標準ライブラリと答えない。** glob の取り込みはプレリュードの名前を隠す名前を
//! 持ち込みうるためである(`use crate::変換::*;` が自作の `trait From` を持ち込む)。標準ライブラリの外の glob の取り込み先から定義をたどれればその定義と答え、
//! たどれなければ(取り込み先のモジュールが再公開の glob を持つときなど)定義をたどれないと答えて欠落に数え、黙って標準ライブラリにしない。
//! 見える glob の取り込みが標準ライブラリのモジュールだけなら、その名前は標準ライブラリの項目である。

use std::path::PathBuf;

use super::super::module_path::モジュールパス;
use super::import_origin::{取り込み元の問い, 取り込み元を求めた結果};
use super::再公開の追跡::{再公開をたどる探索, 再公開をたどる段数の上限};
use super::{型の在り処の問い, 定義の探索の材料, 定義ブロックの結果, 探す定義の宣言};

/// 書いた位置から見える定義が無い修飾の無い名前の出どころ。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 見える定義の無い名前の出どころ {
    標準ライブラリの項目である,
    取り込んだglobの先に定義がある { パス: PathBuf }, // 定義を書いたファイルのパス
    たどれない,
}

/// 標準ライブラリのクレートの名前。
pub(super) const 標準ライブラリのクレート一覧: [&str; 3] = ["std", "core", "alloc"];

/// Rust 2024 の標準のプレリュードが、修飾も取り込みも無しに名前を見せるトレイト。
const プレリュードのトレイト一覧: [&str; 31] = [
    "Copy",
    "Send",
    "Sized",
    "Sync",
    "Unpin",
    "Drop",
    "Fn",
    "FnMut",
    "FnOnce",
    "AsMut",
    "AsRef",
    "From",
    "Into",
    "TryFrom",
    "TryInto",
    "Clone",
    "Default",
    "Eq",
    "Ord",
    "PartialEq",
    "PartialOrd",
    "ToOwned",
    "ToString",
    "Iterator",
    "IntoIterator",
    "DoubleEndedIterator",
    "ExactSizeIterator",
    "Extend",
    "FromIterator",
    "Future",
    "IntoFuture",
];

impl 型の在り処の問い<'_> {
    /// 修飾の無い問いの名前の出どころを、書いた位置の `use` から求める。書いた位置から見える定義が無いと分かった後に問う。
    pub(super) fn 見える定義の無い名前の出どころを求める(&self, 宣言: 探す定義の宣言, 材料: &定義の探索の材料) -> 見える定義の無い名前の出どころ {
        let Some(ファイル) = 材料.ファイルを探す(self.参照元のパス) else {
            return 見える定義の無い名前の出どころ::たどれない;
        };
        let Some(位置) = ファイル.字句位置一覧.get(self.参照元の行番号.saturating_sub(1)) else {
            return 見える定義の無い名前の出どころ::たどれない;
        };
        let 問い = 取り込み元の問い {
            型名: self.型名,
            実装の位置: 位置,
            在るモジュール: 材料.在るモジュール(),
        };
        match 問い.行一覧から取り込み元を求める(ファイル.行一覧, ファイル.字句位置一覧) {
            取り込み元を求めた結果::取り込んでいる { モジュールパス: 取り込み元 } if 標準ライブラリのモジュールか(&取り込み元) => {
                見える定義の無い名前の出どころ::標準ライブラリの項目である
            }
            取り込み元を求めた結果::取り込んでいない => self.globの取り込み先かプレリュードから出どころを求める(宣言, 材料, 問い.見えるglobの取り込み元一覧(ファイル.行一覧, ファイル.字句位置一覧)),
            取り込み元を求めた結果::取り込んでいる { .. } | 取り込み元を求めた結果::取り込み元が複数ある | 取り込み元を求めた結果::別名のため取り込み元を求められない => {
                見える定義の無い名前の出どころ::たどれない
            }
        }
    }

    // 名前を名乗る取り込みが無い名前の出どころを、見える glob の取り込み先とプレリュードから求める。
    fn globの取り込み先かプレリュードから出どころを求める(
        &self, 宣言: 探す定義の宣言, 材料: &定義の探索の材料, globの取り込み元一覧: Vec<モジュールパス>
    ) -> 見える定義の無い名前の出どころ {
        let (標準の一覧, 標準の外の一覧): (Vec<モジュールパス>, Vec<モジュールパス>) = globの取り込み元一覧.into_iter().partition(標準ライブラリのモジュールか);
        if 標準の外の一覧.is_empty() {
            let プレリュードのトレイトか = 宣言 == 探す定義の宣言::トレイト && プレリュードのトレイト一覧.contains(&self.型名);
            return if !標準の一覧.is_empty() || プレリュードのトレイトか {
                見える定義の無い名前の出どころ::標準ライブラリの項目である
            } else {
                見える定義の無い名前の出どころ::たどれない
            };
        }
        let 探索 = 再公開をたどる探索 { 材料, 型名: self.型名, 宣言 };
        let 見つかった一覧: Vec<PathBuf> = 標準の外の一覧
            .iter()
            .filter_map(|モジュール| match 探索.モジュールから定義をたどる(モジュール, 再公開をたどる段数の上限) {
                定義ブロックの結果::見つかった { パス, .. } => Some(パス),
                定義ブロックの結果::見つからない | 定義ブロックの結果::複数ある | 定義ブロックの結果::別名のため取り込み元を求められない => None,
            })
            .collect();
        match (見つかった一覧.as_slice(), 標準の一覧.is_empty()) {
            ([パス], true) => 見える定義の無い名前の出どころ::取り込んだglobの先に定義がある { パス: パス.clone() },
            _ => 見える定義の無い名前の出どころ::たどれない,
        }
    }
}

// そのモジュールが標準ライブラリのクレートの中か。
fn 標準ライブラリのモジュールか(モジュール: &モジュールパス) -> bool {
    標準ライブラリのクレート一覧.contains(&モジュール.クレート().表記())
}
