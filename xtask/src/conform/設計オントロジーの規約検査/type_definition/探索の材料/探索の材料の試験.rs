//! 定義の探索の材料が、モジュールが走査したソースに在るかを、ファイルのモジュールと波括弧付きのモジュールの両方について答え、
//! 祖先のファイルがあるだけのモジュールを在るとしないことを固定する試験。一括取り込みの取り込み元が「確かに無い」と答える前提である。
//! あわせて、その答えが一括取り込み元の探索を通って、見える定義の無い名前の出どころの答えまで届くことを確かめる。

use std::path::PathBuf;

use super::super::super::module_path::モジュールパス;
use super::super::{型の在り処の問い, 探す定義の宣言の種類, 見える定義の無い名前の出どころ};
use super::定義の探索の材料;

fn 形のファイルを持つ材料() -> 定義の探索の材料 {
    let 行一覧 = ["pub struct 地図;", "pub mod 内 {", "    pub struct 地点;", "}"].map(str::to_string).to_vec();
    定義の探索の材料::生成する(vec![(PathBuf::from("crates/blitz_game/src/形.rs"), 行一覧)])
}

#[test]
fn ファイルのモジュールと波括弧付きのモジュールは在る() {
    let 材料 = 形のファイルを持つ材料();
    assert!(材料.モジュールが在るか(&モジュールパス::区切り一覧から組む(&["blitz_game", "形"])));
    assert!(材料.モジュールが在るか(&モジュールパス::区切り一覧から組む(&["blitz_game", "形", "内"])));
}

// 反証: 祖先のファイル(`形.rs`)があることを在ることとみなすと、実在しない `形::無い子` を在ると答える。
#[test]
fn 祖先のファイルがあるだけのモジュールは在るとしない() {
    let 材料 = 形のファイルを持つ材料();
    assert!(!材料.モジュールが在るか(&モジュールパス::区切り一覧から組む(&["blitz_game", "形", "無い子"])));
}

// 1行に書いた波括弧付きのモジュールは、行の頭がその本体の中に来ないため在ると判定しない。2行に分ければ本体が空でも在る。
// この区別は文書(`_doc/設計/設計オントロジー.md` 6.5節)が書く限界であり、判定を変えたらこの試験と文書を一緒に直す。
#[test]
fn 見出しと同じ行で閉じた波括弧付きのモジュールは在ると判定しない() {
    let 行一覧 = ["pub mod 内 { pub struct 甲; }", "pub mod 空 {}", "pub mod 分けた空 {", "}"].map(str::to_string).to_vec();
    let 材料 = 定義の探索の材料::生成する(vec![(PathBuf::from("crates/blitz_game/src/形.rs"), 行一覧)]);
    assert!(!材料.モジュールが在るか(&モジュールパス::区切り一覧から組む(&["blitz_game", "形", "内"])));
    assert!(!材料.モジュールが在るか(&モジュールパス::区切り一覧から組む(&["blitz_game", "形", "空"])));
    assert!(材料.モジュールが在るか(&モジュールパス::区切り一覧から組む(&["blitz_game", "形", "分けた空"])));
}

// 使う側の `use crate::囲い::内::*;` の後に書いた `Clone` の出どころを、囲いのファイルの原文を与えて求める。
fn 囲いから一括取り込みした名前の出どころ(囲いの行一覧: &[&str]) -> 見える定義の無い名前の出どころ {
    let 使う側 = ["use crate::囲い::内::*;", "", "pub fn 使う(値: &dyn Clone) {}"].map(str::to_string).to_vec();
    let 囲い = 囲いの行一覧.iter().map(|行| (*行).to_string()).collect();
    let 使う側のパス = PathBuf::from("crates/blitz_game/src/試験.rs");
    let 材料 = 定義の探索の材料::生成する(vec![(使う側のパス.clone(), 使う側), (PathBuf::from("crates/blitz_game/src/囲い.rs"), 囲い)]);
    let 問い = 型の在り処の問い {
        型名: "Clone",
        参照元のパス: &使う側のパス,
        参照元の行番号: 3,
    };
    材料.見える定義の無い名前の出どころを求める(&問い, 探す定義の宣言の種類::トレイト)
}

// 反証: 一括取り込み元の探索が取り込み元が在るかを在るモジュールの一覧(ファイルのモジュールだけを載せる)だけで決めると、波括弧付きのモジュールを
// 実在しないと答え、そこから持ち込まない `Clone` をたどれないと答える。在ると分かった答えが出どころの答えまで届くことを確かめる。
#[test]
fn 波括弧付きのモジュールの取り込み元に名前が無ければ標準ライブラリの項目と答える() {
    let 出どころ = 囲いから一括取り込みした名前の出どころ(&["pub mod 内 {", "    pub struct 地点;", "}"]);
    assert_eq!(出どころ, 見える定義の無い名前の出どころ::標準ライブラリの項目である);
}

// 見出しと同じ行で閉じた波括弧付きのモジュールは在ると判定しないため、そこからの一括取り込みはたどれないままにする(文書が書く限界)。
#[test]
fn 見出しと同じ行で閉じた波括弧付きのモジュールの取り込み元はたどれない() {
    let 出どころ = 囲いから一括取り込みした名前の出どころ(&["pub mod 内 { pub struct 地点; }"]);
    assert_eq!(出どころ, 見える定義の無い名前の出どころ::たどれない);
}
