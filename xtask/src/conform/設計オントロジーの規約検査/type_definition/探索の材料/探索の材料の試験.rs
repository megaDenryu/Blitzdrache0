//! 定義の探索の材料が、モジュールが走査したソースに在るかを、ファイルのモジュールと波括弧付きのモジュールの両方について答え、
//! 祖先のファイルがあるだけのモジュールを在るとしないことを固定する試験。一括取り込みの取り込み元が「確かに無い」と答える前提である。

use std::path::PathBuf;

use super::super::super::module_path::モジュールパス;
use super::定義の探索の材料;

fn 形のファイルを持つ材料() -> 定義の探索の材料 {
    let 行一覧 = ["pub struct 地図;", "pub mod 内 {", "    pub struct 地点;", "}"].map(str::to_string).to_vec();
    定義の探索の材料::生成する(vec![(PathBuf::from("crates/blitz_game/src/形.rs"), 行一覧)])
}

#[test]
fn ファイルのモジュールと波括弧付きのモジュールは在る() {
    let 材料 = 形のファイルを持つ材料();
    assert!(材料.モジュールが在るか(&モジュールパス::区切り一覧から組む(&["blitz_game", "形"])));
    assert!(材料.モジュールが在るか(&モジュールパス::区切り一覧から組む(&["blitz_game", "形", "内"])));
}

// 反証: 祖先のファイル(`形.rs`)があることを在ることとみなすと、実在しない `形::無い子` を在ると答える。
#[test]
fn 祖先のファイルがあるだけのモジュールは在るとしない() {
    let 材料 = 形のファイルを持つ材料();
    assert!(!材料.モジュールが在るか(&モジュールパス::区切り一覧から組む(&["blitz_game", "形", "無い子"])));
}
