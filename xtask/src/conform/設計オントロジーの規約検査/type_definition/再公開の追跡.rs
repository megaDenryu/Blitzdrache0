//! 再公開の追跡とは、型の定義の探索(`type_definition.rs`)が `use` から求めた取り込み元のモジュールの直下に定義が無いとき、
//! そのモジュールの直下に書いた `use` の取り込みをたどって定義のモジュールへ行き着く工程のことである。たどる `use` は `pub use` に限らず、可視性(`pub`・`pub(crate)`・無し)を問わない。
//! 可視性を読み分けないのは、私有の取り込みを経由して外から型を取り込むソースを rustc が拒み、実在のソースでは可視性を問わずにたどっても別の定義へ行き着かないためである。
//! 受け取るのは型名と、取り込み元のモジュールパスと、たどってよい残りの段数である。返すのは型の定義の探索と同じ結果である。
//!
//! この工程が要るのは、`use crate::移動::胴体の移動の遷移パラメータ;` のように、定義のモジュール(`crate::移動::移動の入力`)でなく再公開した親のモジュールから
//! 取り込む書き方が普通だからである。取り込み元の直下だけを見ると定義が見つからず、節点のモジュールパスが空になって関係が別の節点へ向き、偽の反例を出す。
//! 取り込み元のモジュールで型名を名乗る取り込みは、そのモジュールの直下に書いたものだけを見る(`取り込み元の問い` にそのモジュールの直下の位置を渡す)。
//! 型名を名乗る取り込みが2つ以上あれば一意に決まらないと答え、`as` の別名で型名を名乗る取り込みは取り込み元を求められないと答える(`取り込み元の問い` と同じ規則)。
//! 残りの段数が尽きたら見つからないと答える。再公開が輪をなすソース(rustc が拒む)で探索を止めるための上限であり、実在の再公開はこの段数より浅い。

use super::super::module_path::enclosing_module::{字句位置の区分, 行の字句位置};
use super::super::module_path::モジュールパス;
use super::definition_candidate::同名の定義の候補;
use super::import_origin::{取り込み元の問い, 取り込み元を求めた結果};
use super::{定義の探索の材料, 定義ブロックの結果};

/// 再公開をたどる段数の上限。
pub const 再公開をたどる段数の上限: usize = 8;

/// 1つの型名について、再公開をたどって定義を探す工程。定義の探索の材料と型名を保持する。
pub struct 再公開をたどる探索<'a> {
    pub 材料: &'a 定義の探索の材料,
    pub 型名: &'a str,
}

impl 再公開をたどる探索<'_> {
    /// そのモジュールの直下の定義を採り、無ければそのモジュールの直下の取り込みをたどる。
    pub fn モジュールから定義をたどる(&self, モジュール: &モジュールパス, 残りの段数: usize) -> 定義ブロックの結果 {
        let 候補一覧 = 同名の定義の候補::全ソースから集める(self.材料, self.型名).into_iter().filter(|候補| 候補.モジュールの直下にあるか(モジュール));
        let 結果 = 定義ブロックの結果::候補から1つ採る(候補一覧);
        if 結果 != 定義ブロックの結果::見つからない || 残りの段数 == 0 {
            return 結果;
        }
        match self.モジュールの直下の取り込み元(モジュール) {
            取り込み元を求めた結果::取り込んでいる { モジュールパス: 次 } => self.モジュールから定義をたどる(&次, 残りの段数 - 1),
            取り込み元を求めた結果::取り込んでいない => 定義ブロックの結果::見つからない,
            取り込み元を求めた結果::取り込み元が複数ある => 定義ブロックの結果::複数ある,
            取り込み元を求めた結果::別名のため取り込み元を求められない => 定義ブロックの結果::別名のため取り込み元を求められない,
        }
    }

    // そのモジュールの直下に書いた取り込みのうち、型名を名乗るものの取り込み元。そのモジュールを持ちうるファイル(モジュールがファイルのモジュールと同じか、その下)だけを読む。
    fn モジュールの直下の取り込み元(&self, モジュール: &モジュールパス) -> 取り込み元を求めた結果 {
        let 直下の位置 = 行の字句位置 {
            モジュール: モジュール.clone(),
            区分: 字句位置の区分::モジュールの直下,
        };
        let 問い = 取り込み元の問い {
            型名: self.型名,
            実装の位置: &直下の位置,
            在るモジュール: self.材料.在るモジュール(),
        };
        let mut 取り込み元一覧: Vec<モジュールパス> = Vec::new();
        for ファイル in self.材料.ファイル一覧() {
            if !モジュールを持ちうるか(&モジュールパス::ファイルのパスから求める(ファイル.パス), モジュール) {
                continue;
            }
            match 問い.行一覧から取り込み元を求める(ファイル.行一覧, ファイル.字句位置一覧) {
                取り込み元を求めた結果::取り込んでいない => {}
                取り込み元を求めた結果::取り込んでいる { モジュールパス: 取り込み元 } => {
                    if !取り込み元一覧.contains(&取り込み元) {
                        取り込み元一覧.push(取り込み元);
                    }
                }
                他の結果 => return 他の結果,
            }
        }
        match 取り込み元一覧.as_slice() {
            [] => 取り込み元を求めた結果::取り込んでいない,
            [取り込み元] => 取り込み元を求めた結果::取り込んでいる {
                モジュールパス: 取り込み元.clone()
            },
            _ => 取り込み元を求めた結果::取り込み元が複数ある,
        }
    }
}

// そのファイルが、そのモジュールの行を持ちうるか。ファイルのモジュールがそのモジュールと同じか、ファイルの中の波括弧付きのモジュールとしてその上にあるときである。
fn モジュールを持ちうるか(ファイルのモジュール: &モジュールパス, モジュール: &モジュールパス) -> bool {
    let (ファイル, 対象) = (ファイルのモジュール.表記(), モジュール.表記());
    !ファイル.is_empty() && (ファイル == 対象 || 対象.starts_with(&format!("{ファイル}::")))
}
