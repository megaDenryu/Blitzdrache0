//! 定義の探索の材料とは、走査したソースのパスとコードだけの行の一覧と、同じ一覧から組んだ在るモジュールの一覧の組のことである。
//! 型かトレイトの定義を探す3つの口(修飾の無い名前の定義の在り処・修飾の無い名前が標準ライブラリの項目か・修飾したパスの定義)は、どれもこの2つを読む。
//!
//! 組で持つのは、在るモジュールの一覧がソース一覧から導かれる値であり、別々に組むと同じソース一覧から2つの一覧が複製されるためである。
//! 構文検査と設計関係の抽出は、この1つの値を構文検査が持ち、抽出は構文検査から借りて問う。
//! 在るモジュールの一覧を構築時に1度だけ組むのは、問いごとに全ソースから組み直すと、問いの数とファイルの数の積に比例した費用になるためである。

use std::path::PathBuf;

use super::super::module_path::在るモジュールの一覧::在るモジュールの一覧;
use super::{修飾したパスを探した結果, 型の在り処の問い, 定義ブロックの結果, 探す定義の宣言};

pub struct 定義の探索の材料 {
    ソース一覧: Vec<(PathBuf, Vec<String>)>,
    在るモジュール一覧: 在るモジュールの一覧,
}

impl 定義の探索の材料 {
    /// 走査したソースの一覧から、在るモジュールの一覧を1度だけ組んで持つ。
    pub fn 生成する(ソース一覧: Vec<(PathBuf, Vec<String>)>) -> Self {
        let 在るモジュール一覧 = 在るモジュールの一覧::ソース一覧から集める(&ソース一覧);
        Self { ソース一覧, 在るモジュール一覧 }
    }

    /// 走査したソースのパスとコードだけの行の一覧。
    pub fn ソース一覧(&self) -> &[(PathBuf, Vec<String>)] {
        &self.ソース一覧
    }

    /// 問いが指す名前の、探す宣言(型なら `struct`・`enum`、トレイトなら `trait`)の定義を探す。
    pub fn 定義の在り処を探す(&self, 問い: &型の在り処の問い<'_>, 宣言: 探す定義の宣言) -> 定義ブロックの結果 {
        問い.定義を探す(宣言, &self.ソース一覧, &self.在るモジュール一覧)
    }

    /// 修飾の無い問いの名前が、`use` で標準ライブラリから取り込んだ名前か、取り込みが無いプレリュードのトレイトの名前か。書いた位置から見える定義が無いと分かった後に問う。
    pub fn 標準ライブラリの項目か(&self, 問い: &型の在り処の問い<'_>, 宣言: 探す定義の宣言) -> bool {
        問い.修飾の無い名前が標準ライブラリの項目か(宣言, &self.ソース一覧, &self.在るモジュール一覧)
    }

    /// 問いの位置に書いた修飾が指すモジュールから、問いの名前の、探す宣言の定義をたどる。
    pub fn 修飾したパスの定義を探す(&self, 問い: &型の在り処の問い<'_>, 修飾: &str, 宣言: 探す定義の宣言) -> 修飾したパスを探した結果 {
        問い.修飾したパスの定義を探す(修飾, 宣言, &self.ソース一覧, &self.在るモジュール一覧)
    }
}
