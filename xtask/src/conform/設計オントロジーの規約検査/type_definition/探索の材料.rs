//! 定義の探索の材料とは、走査したソースのパスとコードだけの行の一覧と、同じ一覧から組んだ行ごとの字句位置の一覧と在るモジュールの一覧の組のことである。
//! 型かトレイトの定義を探す3つの口(修飾の無い名前の定義の在り処・見える定義の無い修飾の無い名前の出どころ・修飾したパスの定義)は、どれもこの組を読む。
//!
//! 組で持つのは、字句位置の一覧と在るモジュールの一覧がソース一覧から導かれる値であり、別々に組むと同じソース一覧から複製されるためである。
//! 構文検査と設計関係の抽出は、この1つの値を構文検査が持ち、抽出は構文検査から借りて問う。
//! 字句位置の一覧と在るモジュールの一覧を構築時に1度だけ組むのは、問いごとにファイルから組み直すと、問いの数とファイルの行の数の積に比例した費用になるためである。

#[cfg(test)]
#[path = "探索の材料/探索の材料の試験.rs"]
mod 探索の材料の試験;

use std::path::{Path, PathBuf};

use super::super::module_path::enclosing_module::行の字句位置;
use super::super::module_path::モジュールパス;
use super::super::module_path::在るモジュールの一覧::在るモジュールの一覧;
use super::{修飾したパスを探した結果, 型の在り処の問い, 定義ブロックの結果, 探す定義の宣言の種類, 見える定義の無い名前の出どころ};

pub struct 定義の探索の材料 {
    ソース一覧: Vec<(PathBuf, Vec<String>)>,
    字句位置の一覧: Vec<Vec<行の字句位置>>, // ソース一覧と同じ並びの、ファイルごとの行ごとの字句位置
    在るモジュール一覧: 在るモジュールの一覧,
}

/// 走査したファイル1つ。パスとコードだけの行の一覧と、同じ並びの行ごとの字句位置を借りて持つ。
#[derive(Clone, Copy)]
pub struct 走査したファイル<'a> {
    pub パス: &'a Path,
    pub 行一覧: &'a [String],
    pub 字句位置一覧: &'a [行の字句位置],
}

impl 定義の探索の材料 {
    /// 走査したソースの一覧から、行ごとの字句位置の一覧と在るモジュールの一覧を1度だけ組んで持つ。
    pub fn 生成する(ソース一覧: Vec<(PathBuf, Vec<String>)>) -> Self {
        let 在るモジュール一覧 = 在るモジュールの一覧::ソース一覧から集める(&ソース一覧);
        let 字句位置の一覧 = ソース一覧.iter().map(|(パス, 行一覧)| モジュールパス::ファイルのパスから求める(パス).行ごとの字句位置一覧(行一覧)).collect();
        Self {
            ソース一覧,
            字句位置の一覧,
            在るモジュール一覧,
        }
    }

    /// 走査したソースのパスとコードだけの行の一覧。
    pub fn ソース一覧(&self) -> &[(PathBuf, Vec<String>)] {
        &self.ソース一覧
    }

    /// 起点の予約語の無いパスの起点を決める、在るモジュールの一覧。
    pub(super) fn 在るモジュール(&self) -> &在るモジュールの一覧 {
        &self.在るモジュール一覧
    }

    /// そのモジュールが走査したソースに在るか。ファイルから推定したモジュールか、ファイルの中の波括弧付きのモジュール(`mod 名 { … }`)として、
    /// その本体に1行以上を持つものである。在るモジュールの一覧を先に引き、無ければ行ごとの字句位置を見る(一覧は波括弧付きのモジュールを数えないため)。
    pub(super) fn モジュールが在るか(&self, モジュール: &モジュールパス) -> bool {
        self.在るモジュール一覧.含むか(モジュール) || self.字句位置の一覧.iter().flatten().any(|位置| 位置.モジュール == *モジュール)
    }

    /// 走査した全ファイルを、行ごとの字句位置と組にして並べる。
    pub(super) fn ファイル一覧(&self) -> impl Iterator<Item = 走査したファイル<'_>> {
        self.ソース一覧.iter().zip(&self.字句位置の一覧).map(|((パス, 行一覧), 字句位置一覧)| 走査したファイル { パス, 行一覧, 字句位置一覧 })
    }

    /// そのパスの走査したファイル。走査していなければ無しである。
    pub(super) fn ファイルを探す(&self, パス: &Path) -> Option<走査したファイル<'_>> {
        self.ファイル一覧().find(|ファイル| ファイル.パス == パス)
    }

    /// 問いが指す名前の、探す宣言(型なら `struct`・`enum`、トレイトなら `trait`)の定義を探す。
    pub fn 定義の在り処を探す(&self, 問い: &型の在り処の問い<'_>, 宣言: 探す定義の宣言の種類) -> 定義ブロックの結果 {
        問い.定義を探す(宣言, self)
    }

    /// 書いた位置から見える定義が無いと分かった修飾の無い名前が、標準ライブラリの項目か、一括取り込み(`use a::*;`)の取り込み元の定義か、たどれないか。
    pub fn 見える定義の無い名前の出どころを求める(&self, 問い: &型の在り処の問い<'_>, 宣言: 探す定義の宣言の種類) -> 見える定義の無い名前の出どころ {
        問い.見える定義の無い名前の出どころを求める(宣言, self)
    }

    /// 問いの位置に書いた修飾が指すモジュールから、問いの名前の、探す宣言の定義をたどる。
    pub fn 修飾したパスの定義を探す(&self, 問い: &型の在り処の問い<'_>, 修飾: &str, 宣言: 探す定義の宣言の種類) -> 修飾したパスを探した結果 {
        問い.修飾したパスの定義を探す(修飾, 宣言, self)
    }
}
