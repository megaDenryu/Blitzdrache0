//! 一括取り込み元の探索とは、書いた位置から見える一括取り込み(`use a::*;`・`pub use a::*;`。取り込む位置から見える、取り込み元のモジュールの名前を全部まとめて取り込むこと。`use super::*;` は親の私有の項目も持ち込む)の
//! 取り込み元のモジュール1つについて、探す名前がそこから持ち込まれるかを答える工程のことである。受け取るのは取り込み元のモジュール、返すのは次の4つのどれかである。
//! そのモジュールか、名前を名乗る再公開の先に定義がある。名前を名乗る取り込みで標準ライブラリから取り込んでいる。そのモジュールにその名前が確かに無い。先をたどれない。
//!
//! 答えは次の順で決める。そのモジュールそのものが走査したソースに無ければ(外部クレートや、祖先のファイルだけがあって実在しないモジュール)、何を公開しているかを読めないため先をたどれない。
//! 次に、そのモジュールのマクロの呼び出しの中に同じ名前の定義があれば、マクロが何を展開するかを読めないため、直下に定義があっても先をたどれない。
//! 次に、直下に同じ名前の定義があれば定義がある。無ければ直下の取り込みを見る。名前を名乗る取り込みが標準ライブラリからなら標準ライブラリから名前を取り込んでいる、
//! それ以外なら再公開をたどって定義があるか先をたどれないかを答える。一括取り込みがあれば、その先がさらに名前を持ち込みうるため先をたどれない(黙って「無い」にしない)。
//! どれも無ければ確かに無い。
//! 走査したソースに在るモジュールとは、ファイルのモジュールか、見出しの `{` と閉じの `}` を別の行に書いた波括弧付きのモジュールである。
//! 1行に書いたモジュール(`pub mod 内 { pub struct 甲; }`・`pub mod 空 {}`)は在ると判定しないため、それを取り込み元とする一括取り込みは先をたどれない。
//! 「確かに無い」を「先をたどれない」と分けるのは、取り込み元が名前を持たないと分かっている一括取り込みのせいで、プレリュードのトレイト(`Clone`)を標準ライブラリと答えられなくなるのを避けるためである。
//! 取り込み元に `Clone` の定義が無いと分かっているのに定義をたどれないと答えると、`impl Clone for 状態` の関数を除外できず、状態を受けて返す処理の宣言の法則の偽の反例になる。
//!
//! 注意: この探索は可視性を読まないため、一括取り込みが私有の項目を飛ばすことを知らない。子孫でないモジュールからの `use crate::形::*;` で `形` が私有の
//! `trait Clone` を持つと、rustc は標準ライブラリの `Clone` と解決するが、この探索は「定義がある」と答え、プリミティブな関係の目的語が私有の自作の `Clone` になる。
//! `impl Clone for 状態` の関数を除外できないときは状態を受けて返す処理の宣言の法則の偽の反証になり `cargo xtask design-verify` を落とすが、
//! `fn 使う(値: &dyn Clone)` の引数に取る関係のように法則が問わない関係は、誤ったまま何も落とさずに残りうる。抽出器の保証範囲の限界である(`_doc/設計/設計オントロジー.md` 6.5節)。

use std::path::PathBuf;

use super::super::module_path::enclosing_module::{字句位置の区分, 行の字句位置};
use super::super::module_path::モジュールパス;
use super::definition_candidate::同名の定義の候補;
use super::import_origin::{取り込み元の問い, 取り込み元を求めた結果};
use super::再公開の追跡::{モジュールを持ちうるか, 再公開をたどる探索, 再公開をたどる段数の上限};
use super::定義ブロックの結果;
use super::標準ライブラリの名前の表::標準ライブラリのモジュールか;

/// 一括取り込みの取り込み元のモジュール1つについて、探す名前がそこから持ち込まれるかの答え。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 一括取り込み元で名前を探した答え {
    定義がある { パス: PathBuf }, // 定義を書いたファイルのパス
    標準ライブラリから名前を取り込んでいる,
    確かに無い,
    先をたどれない,
}

impl 再公開をたどる探索<'_> {
    /// 一括取り込みの取り込み元のモジュールの直下の定義を採り、無ければそのモジュールの直下の取り込みを見て、探す名前がそこから持ち込まれるかを答える。
    pub fn 一括取り込み元で名前を探す(&self, モジュール: &モジュールパス) -> 一括取り込み元で名前を探した答え {
        if !self.材料.モジュールが在るか(モジュール) {
            return 一括取り込み元で名前を探した答え::先をたどれない;
        }
        let 候補一覧 = 同名の定義の候補::全ソースから集める(self.材料, self.型名, self.宣言);
        if 候補一覧.iter().any(|候補| 候補.モジュールのマクロの呼び出しの中にあるか(モジュール)) {
            return 一括取り込み元で名前を探した答え::先をたどれない;
        }
        match 定義ブロックの結果::候補から1つ採る(候補一覧.into_iter().filter(|候補| 候補.モジュールの直下にあるか(モジュール))) {
            定義ブロックの結果::見つかった { パス, .. } => 一括取り込み元で名前を探した答え::定義がある { パス },
            定義ブロックの結果::見つからない => self.直下に定義の無いモジュールの取り込みを見る(モジュール),
            定義ブロックの結果::複数ある | 定義ブロックの結果::別名のため取り込み元を求められない => 一括取り込み元で名前を探した答え::先をたどれない,
        }
    }

    // 直下に同じ名前の定義が無いモジュールについて、その直下の取り込みから、探す名前がそこから持ち込まれるかを答える。
    fn 直下に定義の無いモジュールの取り込みを見る(&self, モジュール: &モジュールパス) -> 一括取り込み元で名前を探した答え {
        match self.モジュールの直下の取り込み元(モジュール) {
            取り込み元を求めた結果::取り込んでいる { モジュールパス: 次 } if 標準ライブラリのモジュールか(&次) => {
                一括取り込み元で名前を探した答え::標準ライブラリから名前を取り込んでいる
            }
            取り込み元を求めた結果::取り込んでいる { モジュールパス: 次 } => match self.モジュールから定義をたどる(&次, 再公開をたどる段数の上限 - 1) {
                定義ブロックの結果::見つかった { パス, .. } => 一括取り込み元で名前を探した答え::定義がある { パス },
                定義ブロックの結果::見つからない | 定義ブロックの結果::複数ある | 定義ブロックの結果::別名のため取り込み元を求められない => {
                    一括取り込み元で名前を探した答え::先をたどれない
                }
            },
            取り込み元を求めた結果::取り込み元が複数ある | 取り込み元を求めた結果::別名のため取り込み元を求められない => 一括取り込み元で名前を探した答え::先をたどれない,
            取り込み元を求めた結果::取り込んでいない if self.モジュールの直下に一括取り込みがあるか(モジュール) => 一括取り込み元で名前を探した答え::先をたどれない,
            取り込み元を求めた結果::取り込んでいない => 一括取り込み元で名前を探した答え::確かに無い,
        }
    }

    // そのモジュールの直下に一括取り込みを書いたか。そのモジュールを持ちうるファイルだけを読む。
    fn モジュールの直下に一括取り込みがあるか(&self, モジュール: &モジュールパス) -> bool {
        let 直下の位置 = 行の字句位置 {
            モジュール: モジュール.clone(),
            区分: 字句位置の区分::モジュールの直下,
        };
        let 問い = 取り込み元の問い {
            型名: self.型名,
            実装の位置: &直下の位置,
            在るモジュール: self.材料.在るモジュール(),
        };
        self.材料
            .ファイル一覧()
            .filter(|ファイル| モジュールを持ちうるか(&モジュールパス::ファイルのパスから求める(ファイル.パス), モジュール))
            .any(|ファイル| !問い.見える一括取り込みの取り込み元一覧(ファイル.行一覧, ファイル.字句位置一覧).is_empty())
    }
}
