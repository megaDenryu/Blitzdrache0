//! 一括取り込み先の探索とは、書いた位置から見える一括取り込み(`use a::*;`・`pub use a::*;`。取り込み元のモジュールの公開された名前を全部まとめて取り込むこと)の
//! 取り込み元のモジュール1つについて、探す名前がそこから持ち込まれるかを答える工程のことである。受け取るのは取り込み元のモジュール、返すのは次の4つのどれかである。
//! そのモジュールか、名前を名乗る再公開の先に定義がある。名前を名乗る取り込みで標準ライブラリから取り込んでいる。そのモジュールにその名前が確かに無い。先をたどれない。
//!
//! 「確かに無い」と答えるのは、走査したソースにそのモジュールを持ちうるファイルがあり、その直下に同じ名前の定義も、その名前を名乗る取り込みも、一括取り込みも無いときだけである。
//! 一括取り込みを持つモジュールは、その先がさらに名前を持ち込みうるため先をたどれないと答える(黙って「無い」にしない)。
//! 走査したソースに無いモジュール(外部クレート)も、何を公開しているかを読めないため先をたどれないと答える。
//! 「確かに無い」を「先をたどれない」と分けるのは、取り込み先が名前を持たないと分かっている一括取り込みのせいで、プレリュードのトレイト(`Clone`)を標準ライブラリと答えられなくなるのを避けるためである。
//! 取り込み先に `Clone` の定義が無いと分かっているのに定義をたどれないと答えると、`impl Clone for 状態` の関数を除外できず、状態を受けて返す処理の宣言の法則の偽の反例になる。

use std::path::PathBuf;

use super::super::module_path::enclosing_module::{字句位置の区分, 行の字句位置};
use super::super::module_path::モジュールパス;
use super::definition_candidate::同名の定義の候補;
use super::import_origin::{取り込み元の問い, 取り込み元を求めた結果};
use super::再公開の追跡::{モジュールを持ちうるか, 再公開をたどる探索, 再公開をたどる段数の上限};
use super::定義ブロックの結果;
use super::標準ライブラリの名前の表::標準ライブラリのモジュールか;

/// 一括取り込みの取り込み元のモジュール1つについて、探す名前がそこから持ち込まれるかの答え。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 一括取り込み先で名前を探した答え {
    定義がある { パス: PathBuf }, // 定義を書いたファイルのパス
    標準ライブラリから名前を取り込んでいる,
    確かに無い,
    先をたどれない,
}

impl 再公開をたどる探索<'_> {
    /// 一括取り込みの取り込み元のモジュールの直下の定義を採り、無ければそのモジュールの直下の取り込みを見て、探す名前がそこから持ち込まれるかを答える。
    pub fn 一括取り込み先で名前を探す(&self, モジュール: &モジュールパス) -> 一括取り込み先で名前を探した答え {
        if !self.材料.ファイル一覧().any(|ファイル| モジュールを持ちうるか(&モジュールパス::ファイルのパスから求める(ファイル.パス), モジュール)) {
            return 一括取り込み先で名前を探した答え::先をたどれない;
        }
        let 候補一覧 = 同名の定義の候補::全ソースから集める(self.材料, self.型名, self.宣言).into_iter().filter(|候補| 候補.モジュールの直下にあるか(モジュール));
        match 定義ブロックの結果::候補から1つ採る(候補一覧) {
            定義ブロックの結果::見つかった { パス, .. } => 一括取り込み先で名前を探した答え::定義がある { パス },
            定義ブロックの結果::見つからない => self.直下に定義の無いモジュールの取り込みを見る(モジュール),
            定義ブロックの結果::複数ある | 定義ブロックの結果::別名のため取り込み元を求められない => 一括取り込み先で名前を探した答え::先をたどれない,
        }
    }

    // 直下に同じ名前の定義が無いモジュールについて、その直下の取り込みから、探す名前がそこから持ち込まれるかを答える。
    fn 直下に定義の無いモジュールの取り込みを見る(&self, モジュール: &モジュールパス) -> 一括取り込み先で名前を探した答え {
        match self.モジュールの直下の取り込み元(モジュール) {
            取り込み元を求めた結果::取り込んでいる { モジュールパス: 次 } if 標準ライブラリのモジュールか(&次) => {
                一括取り込み先で名前を探した答え::標準ライブラリから名前を取り込んでいる
            }
            取り込み元を求めた結果::取り込んでいる { モジュールパス: 次 } => match self.モジュールから定義をたどる(&次, 再公開をたどる段数の上限 - 1) {
                定義ブロックの結果::見つかった { パス, .. } => 一括取り込み先で名前を探した答え::定義がある { パス },
                定義ブロックの結果::見つからない | 定義ブロックの結果::複数ある | 定義ブロックの結果::別名のため取り込み元を求められない => {
                    一括取り込み先で名前を探した答え::先をたどれない
                }
            },
            取り込み元を求めた結果::取り込み元が複数ある | 取り込み元を求めた結果::別名のため取り込み元を求められない => 一括取り込み先で名前を探した答え::先をたどれない,
            取り込み元を求めた結果::取り込んでいない if self.モジュールの直下に一括取り込みがあるか(モジュール) => 一括取り込み先で名前を探した答え::先をたどれない,
            取り込み元を求めた結果::取り込んでいない => 一括取り込み先で名前を探した答え::確かに無い,
        }
    }

    // そのモジュールの直下に一括取り込みを書いたか。そのモジュールを持ちうるファイルだけを読む。
    fn モジュールの直下に一括取り込みがあるか(&self, モジュール: &モジュールパス) -> bool {
        let 直下の位置 = 行の字句位置 {
            モジュール: モジュール.clone(),
            区分: 字句位置の区分::モジュールの直下,
        };
        let 問い = 取り込み元の問い {
            型名: self.型名,
            実装の位置: &直下の位置,
            在るモジュール: self.材料.在るモジュール(),
        };
        self.材料
            .ファイル一覧()
            .filter(|ファイル| モジュールを持ちうるか(&モジュールパス::ファイルのパスから求める(ファイル.パス), モジュール))
            .any(|ファイル| !問い.見える一括取り込みの取り込み元一覧(ファイル.行一覧, ファイル.字句位置一覧).is_empty())
    }
}
