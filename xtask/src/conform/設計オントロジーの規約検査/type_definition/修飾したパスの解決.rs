//! 修飾したパスの解決とは、型の表記に書いたパスの修飾(`fmt`・`crate::a`・`blitz_math`)がどのモジュールを指すかを、表記を書いた位置の `use` の取り込みから求め、
//! そのモジュールから名前の定義をたどる工程のことである。受け取るのは型の在り処の問い(名前と、それを書いた行)と修飾、返すのは探した結果である。
//!
//! 修飾の頭は次の順に読む。`crate`・`self`・`super` は、書いた位置のモジュールからの起点である。頭を名乗る `use` の取り込みがあれば、取り込んだモジュールである
//! (`use std::fmt;` の後の `fmt::Result` は `std::fmt::Result`)。どちらでもなければ、書いた位置の子のモジュールか外部クレートである(`use` のパスの読み方と同じ)。
//! 頭が書いた位置から見える型かトレイトの名前なら、名前はその関連項目(`型::関連型`)であり、どのモジュールの定義でもないため、そう答える。
//! 頭を `as` の別名で名乗る取り込みと、頭を名乗る取り込みが2つ以上あるときは、取り込み元を1つに決められないため見つからないと答え、推測で別のモジュールを採らない。
//! 修飾が標準ライブラリ(`std`・`core`・`alloc`)のモジュールを指すなら、定義をたどらずにそう答える。

use std::path::PathBuf;

use super::super::module_path::モジュールパス;
use super::super::module_path::在るモジュールの一覧::在るモジュールの一覧;
use super::import_origin::{取り込み元の問い, 取り込み元を求めた結果};
use super::再公開の追跡::{再公開をたどる探索, 再公開をたどる段数の上限};
use super::{型の在り処の問い, 定義ブロックの結果, 探す定義の宣言};

/// 標準ライブラリのクレートの名前。
const 標準ライブラリのクレート一覧: [&str; 3] = ["std", "core", "alloc"];

/// 修飾したパスの名前の定義を探した結果。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 修飾したパスを探した結果 {
    標準ライブラリの項目である,
    見つかった { パス: PathBuf }, // 定義を書いたファイルのパス
    見つからない,
    修飾の頭が型である,
}

impl 型の在り処の問い<'_> {
    /// 問いの位置に書いた修飾が指すモジュールから、問いの名前の、探す宣言の定義をたどる。
    pub(super) fn 修飾したパスの定義を探す(&self, 修飾: &str, 宣言: 探す定義の宣言, ソース一覧: &[(PathBuf, Vec<String>)], 在るモジュール: &在るモジュールの一覧) -> 修飾したパスを探した結果 {
        let 頭 = 修飾.split("::").next().unwrap_or_default().trim();
        if self.頭が型かトレイトの名前か(頭, ソース一覧, 在るモジュール) {
            return 修飾したパスを探した結果::修飾の頭が型である;
        }
        let Some(モジュール) = self.修飾が指すモジュール(修飾, 頭, ソース一覧, 在るモジュール) else {
            return 修飾したパスを探した結果::見つからない;
        };
        if 標準ライブラリのクレート一覧.contains(&モジュール.クレート().表記()) {
            return 修飾したパスを探した結果::標準ライブラリの項目である;
        }
        let 探索 = 再公開をたどる探索 {
            ソース一覧,
            在るモジュール,
            型名: self.型名,
            宣言,
        };
        match 探索.モジュールから定義をたどる(&モジュール, 再公開をたどる段数の上限) {
            定義ブロックの結果::見つかった { パス, .. } => 修飾したパスを探した結果::見つかった { パス },
            定義ブロックの結果::見つからない | 定義ブロックの結果::複数ある | 定義ブロックの結果::別名のため取り込み元を求められない => 修飾したパスを探した結果::見つからない,
        }
    }

    // 修飾の頭が、問いの位置から見える型かトレイトの名前か。`Self` は実装の対象の型である。
    fn 頭が型かトレイトの名前か(&self, 頭: &str, ソース一覧: &[(PathBuf, Vec<String>)], 在るモジュール: &在るモジュールの一覧) -> bool {
        if 頭 == "Self" {
            return true;
        }
        let 頭の問い = 型の在り処の問い {
            型名: 頭,
            参照元のパス: self.参照元のパス,
            参照元の行番号: self.参照元の行番号,
        };
        [探す定義の宣言::型, 探す定義の宣言::トレイト]
            .into_iter()
            .any(|宣言| !matches!(頭の問い.定義を探す(宣言, ソース一覧, 在るモジュール), 定義ブロックの結果::見つからない))
    }

    // 修飾が指す絶対のモジュールパス。頭を名乗る取り込みの取り込み元を1つに決められなければ無しである。
    fn 修飾が指すモジュール(&self, 修飾: &str, 頭: &str, ソース一覧: &[(PathBuf, Vec<String>)], 在るモジュール: &在るモジュールの一覧) -> Option<モジュールパス> {
        let 行一覧 = ソース一覧.iter().find(|(パス, _)| パス == self.参照元のパス).map(|(_, 行一覧)| 行一覧)?;
        let 字句位置一覧 = モジュールパス::ファイルのパスから求める(self.参照元のパス).行ごとの字句位置一覧(行一覧);
        let 位置 = 字句位置一覧.get(self.参照元の行番号.saturating_sub(1))?;
        if matches!(頭, "crate" | "self" | "super") {
            return Some(位置.モジュール.書かれたパスを絶対にする(修飾));
        }
        let 問い = 取り込み元の問い {
            型名: 頭, 実装の位置: 位置, 在るモジュール
        };
        match 問い.行一覧から取り込み元を求める(行一覧, &字句位置一覧) {
            取り込み元を求めた結果::取り込んでいる { モジュールパス: 取り込み元 } => {
                let 残り: Vec<&str> = 修飾.split("::").map(str::trim).collect();
                Some(取り込み元.下へ繋ぐ(&残り))
            }
            取り込み元を求めた結果::取り込んでいない => Some(位置.モジュール.書かれたパスを在るモジュールで絶対にする(修飾, 在るモジュール)),
            取り込み元を求めた結果::取り込み元が複数ある | 取り込み元を求めた結果::別名のため取り込み元を求められない => None,
        }
    }
}
