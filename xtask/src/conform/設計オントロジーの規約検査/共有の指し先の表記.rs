//! コードだけの行の中から、共有の指し先(参照を数えて1つの実体を共有する `Arc`・`Rc`・`Weak`)の表記を読む。依存を持たない純粋な関数だけを置く。
//! 受け取るのは行、返すのはその行に現れる共有の指し先の一覧である。`Arc` は中身の型の表記を山括弧の対応を数えて切り出して運ぶ。
//! 名前は識別子の境界で探すため、`std::sync::Arc<型>` の修飾した表記にも当たり、`Arcの設定` のような識別子の一部には当たらない。
//! `Arc` の修飾は、設計関係の抽出器が保持する関係を読むときと同じ一覧(`blitz_design_verification::標準の共有の包みの表記か`)で判定する。
//! 修飾の無い `Arc` と `std::sync::Arc`・`alloc::sync::Arc` だけを標準の `Arc` と読み、ほかの修飾の `Arc`(`別の::Arc<型>`)は同じ名前の別の型でありうるため、標準でない修飾の `Arc` として返す。
//! 2つの読み手が別々の一覧を持つと、一方が許す `Arc` をもう一方が読めないという食い違いが起きるためである。

use blitz_design_verification::標準の共有の包みの表記か;

use super::identifier_boundary::{識別子として現れる位置一覧, 識別子の文字か};

/// 行に現れた共有の指し先1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(super) enum 共有の指し先 {
    Arc { 中身の型の表記: String }, // 標準の表記の `Arc`。中身は山括弧の中身であり、閉じる山括弧が同じ行に無ければ行の残りの全部である
    標準でない修飾のArc { 書かれた文字列: String },
    参照を数える別の指し先 { 名前: &'static str },
}

/// 純粋データが持てない、参照を数える別の指し先の名前。`Weak` は `Arc` と `Rc` のどちらの弱い指し先にも当たる。
const 参照を数える別の指し先一覧: [&str; 2] = ["Rc", "Weak"];

/// 行に現れる共有の指し先を、行の中の位置の順に並べる。名前の直後(空白を除く)が `<` でない現れ(`Arc::new` など)は型の表記でないため数えない。
pub(super) fn 行の共有の指し先一覧(行: &str) -> Vec<共有の指し先> {
    let mut 一覧: Vec<(usize, 共有の指し先)> = 型引数を取る現れ一覧(行, "Arc").into_iter().map(|(位置, 中身)| (位置, arcの指し先(行, 位置, 中身))).collect();
    for 名前 in 参照を数える別の指し先一覧 {
        一覧.extend(型引数を取る現れ一覧(行, 名前).into_iter().map(|(位置, _)| (位置, 共有の指し先::参照を数える別の指し先 { 名前 })));
    }
    一覧.sort_by_key(|(位置, _)| *位置);
    一覧.into_iter().map(|(_, 指し先)| 指し先).collect()
}

// 行の `位置` に現れた `Arc` を、前に続く修飾まで含めた表記で標準か見分ける。
fn arcの指し先(行: &str, 位置: usize, 中身の型の表記: String) -> 共有の指し先 {
    let 書かれた文字列 = 修飾を含む書かれた文字列(&行[..位置], "Arc");
    if 標準の共有の包みの表記か(&書かれた文字列) {
        共有の指し先::Arc { 中身の型の表記 }
    } else {
        共有の指し先::標準でない修飾のArc { 書かれた文字列 }
    }
}

// 名前の前に続くパスの修飾(`a::b::`)を、空白を除いて名前へつないだ表記。修飾の途中が識別子で終わらない形(`<T as X>::Arc`・先頭の `::`)は
// `::` から始まる表記になり、標準の表記に当たらない。
fn 修飾を含む書かれた文字列(前: &str, 名前: &str) -> String {
    let mut 書かれた文字列 = 名前.to_string();
    let mut 残り = 前;
    while let Some(区切りの前) = 残り.trim_end().strip_suffix("::") {
        let 区切りの前 = 区切りの前.trim_end();
        let 開始 = 区切りの前.char_indices().rev().take_while(|(_, 文字)| 識別子の文字か(*文字)).last().map_or(区切りの前.len(), |(位置, _)| 位置);
        書かれた文字列 = format!("{}::{書かれた文字列}", &区切りの前[開始..]);
        if 開始 == 区切りの前.len() {
            break;
        }
        残り = &区切りの前[..開始];
    }
    書かれた文字列
}

// 名前が識別子の境界で現れ、直後に `<` が続く位置と、その山括弧の中身の表記。
fn 型引数を取る現れ一覧(行: &str, 名前: &str) -> Vec<(usize, String)> {
    識別子として現れる位置一覧(行, 名前)
        .into_iter()
        .filter_map(|位置| {
            let 後ろ = 行[位置 + 名前.len()..].trim_start().strip_prefix('<')?;
            Some((位置, 山括弧の中身(後ろ).trim().to_string()))
        })
        .collect()
}

// 開いた山括弧の直後からの文字列のうち、対応する閉じる山括弧の手前まで。
fn 山括弧の中身(開いた後ろ: &str) -> &str {
    let mut 深さ = 0usize;
    for (位置, 文字) in 開いた後ろ.char_indices() {
        match 文字 {
            '<' => 深さ += 1,
            '>' if 深さ == 0 => return &開いた後ろ[..位置],
            '>' => 深さ -= 1,
            _ => {}
        }
    }
    開いた後ろ
}
