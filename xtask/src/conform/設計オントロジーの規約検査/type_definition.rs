//! 型の定義の探索。呼び出し連鎖の中の独立した工程であり、受け取るのは全ソースと型の在り処の問い(型の名前と、その名前を書いている行の位置)、
//! 返すのは定義ブロック(直前の属性の行を含む)とそのファイルのパスと定義の位置のモジュールか、見つからないか、同名の定義が複数あって一意に決まらないか、`as` の別名のため取り込み元を求められないかである。
//! 同じ探し方で `trait` の定義も探す(`探す定義の宣言の種類`)。関数の署名の `impl トレイト`・`dyn トレイト` が名指すトレイトの定義をたどるためである。
//! 型の同一性は「定義の位置のモジュール + 型名」である。定義の位置のモジュールとは、定義のファイルから推定したモジュールパスの下へ、定義の行を囲む `mod 名 { … }` の名前を外側から繋いだものである(子のモジュール `type_definition/definition_candidate.rs`)。
//! 実装の位置のモジュールの直下に同名の定義があればそれを採り、無ければ実装の位置のモジュールの直下の `use` 行から取り込み元のモジュールパスを求めて、そのモジュールの直下の定義を採る(子のモジュール `type_definition/import_origin.rs`)。
//! 同じファイルでも、別の波括弧付きのモジュールの定義と関数の本体などの局所の定義は、実装が書いた型名の定義として採らない。Rust ではそれらは実装の位置から修飾か `use` 無しには名指せず、局所の定義はその本体の外から見えないためである。
//! そうした定義しか無く `use` も無ければ一意に決まらないと返し、黙って別の定義を採らない。実装が局所の位置にあり、同じファイルに同名の局所の定義があるときと、実装の位置のモジュールのマクロの呼び出しの中(`素通し! { … }`)に同名の定義があるときは、それらが名前を隠しうるため一意に決まらないと返す。
//! 取り込み元のモジュールの直下に定義が無ければ、そのモジュールの直下の `use` を、可視性を問わずにたどる(子のモジュール `type_definition/再公開の追跡.rs`)。
//! 明示した取り込み元を求められないときは、他のモジュールの同名定義を推測で採らない。型名を名乗る取り込みの取り込み元が複数ある(cfg で切り替わる取り込み)ときと、実装の位置のモジュールの直下の定義と型名を名乗る `use` が同時にあるときは、一意に決まらないと返す。

