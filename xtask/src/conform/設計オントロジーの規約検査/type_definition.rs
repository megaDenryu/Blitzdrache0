/// ある型の定義がどこに在るかの問い。型の名前と、その名前を書いている行の位置の組である。
pub struct 型の在り処の問い<'a> {
    pub 型名: &'a str,
    pub 参照元のパス: &'a Path,
    pub 参照元の行番号: usize,
}

/// 型の定義の探索の結果。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 定義ブロックの結果 {
    見つかった { 定義: String, パス: PathBuf, モジュール: モジュールパス }, // モジュールは定義の位置のモジュールである
    見つからない,
    複数ある,
    別名のため取り込み元を求められない,
}

impl 定義ブロックの結果 {
    // 候補の一覧から1つだけ採る。1つも無ければ見つからない、2つ以上なら複数ある。
    fn 候補から1つ採る(mut 候補一覧: impl Iterator<Item = 同名の定義の候補>) -> Self {
        match (候補一覧.next(), 候補一覧.next()) {
            (Some(候補), None) => Self::見つかった {
                定義: 候補.定義,
                パス: 候補.パス,
                モジュール: 候補.位置.モジュール,
            },
            (Some(_), Some(_)) => Self::複数ある,
            (None, _) => Self::見つからない,
        }
    }
}

impl 型の在り処の問い<'_> {
    /// 走査したソースから、この問いが指す名前の、探す宣言の定義を探す。探し方は宣言の種類によらず同じである。字句位置と在るモジュールの一覧は、
    /// 材料が同じソース一覧から1度だけ組んだものを読む(問いごとに組み直すと、問いの数とファイルの行の数の積に比例した費用になる)。
    fn 定義を探す(&self, 宣言: 探す定義の宣言の種類, 材料: &定義の探索の材料) -> 定義ブロックの結果 {
        let Some(ファイル) = 材料.ファイルを探す(self.参照元のパス) else {
            return 定義ブロックの結果::見つからない;
        };
        let Some(実装の位置) = ファイル.字句位置一覧.get(self.参照元の行番号.saturating_sub(1)) else {
            return 定義ブロックの結果::見つからない;
        };
        let 同じファイルの候補一覧 = 同名の定義の候補::全ソースから集める(材料, self.型名, 宣言).into_iter().filter(|候補| 候補.パス == self.参照元のパス);
        let (直下の候補一覧, 採らない候補一覧): (Vec<同名の定義の候補>, Vec<同名の定義の候補>) = 同じファイルの候補一覧.partition(|候補| 候補.モジュールの直下にあるか(&実装の位置.モジュール));
        if 採らない候補一覧.iter().any(|候補| 候補.実装の名前を隠しうるか(実装の位置)) {
            return 定義ブロックの結果::複数ある;
        }
        let 取り込み元 = (取り込み元の問い {
            型名: self.型名,
            実装の位置,
            在るモジュール: 材料.在るモジュール(),
        })
        .行一覧から取り込み元を求める(ファイル.行一覧, ファイル.字句位置一覧);
        if !直下の候補一覧.is_empty() {
            return match 取り込み元 {
                取り込み元を求めた結果::取り込んでいない => 定義ブロックの結果::候補から1つ採る(直下の候補一覧.into_iter()),
                取り込み元を求めた結果::取り込んでいる { .. } | 取り込み元を求めた結果::取り込み元が複数ある | 取り込み元を求めた結果::別名のため取り込み元を求められない => {
                    定義ブロックの結果::複数ある
                }
            };
        }
        match 取り込み元 {
            取り込み元を求めた結果::別名のため取り込み元を求められない => 定義ブロックの結果::別名のため取り込み元を求められない,
            取り込み元を求めた結果::取り込んでいる {
                モジュールパス: 定義のモジュール
            } => (再公開をたどる探索 { 材料, 型名: self.型名, 宣言 }).モジュールから定義をたどる(&定義のモジュール, 再公開をたどる段数の上限),
            取り込み元を求めた結果::取り込み元が複数ある => 定義ブロックの結果::複数ある,
            取り込み元を求めた結果::取り込んでいない if !採らない候補一覧.is_empty() => 定義ブロックの結果::複数ある,
            取り込み元を求めた結果::取り込んでいない => 定義ブロックの結果::見つからない,
        }
    }
}
