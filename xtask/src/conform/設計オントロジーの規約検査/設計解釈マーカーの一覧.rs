//! 設計解釈マーカーの正本の一覧。`blitz_design` の `設計解釈マーカー.rs` が宣言するマーカーを列挙し、2つの基底の契約(`M不変データ` と `M共有される不変データ`)と5つの軸ごとの一覧を持つ。
//! 排他の組と、上位の分類を分ける下位の分類の組は、その法則を検査する `分類の排他と網羅の検査.rs` が持つ(組ごとの理由の文言と同じ場所に置くため)。
//! 構文検査と設計関係の抽出が、マーカーの名前をこの一覧からだけ得る。

/// 設計解釈マーカーの一覧。`blitz_design` の `設計解釈マーカー.rs` が宣言するマーカーのうち、検査が照合するものを並べる。選択肢の名前はマーカーの名前をそのまま写す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 設計解釈マーカー {
    M不変データ,
    M共有される不変データ,
    M遷移が受け取る命令,
    Mコマンド,
    M命令の組,
    Mイベント,
    M規則,
    M状態,
    M解釈前の入力,
    M生入力,
    M中間入力,
    M観測,
    M工程,
    M値オブジェクト,
    Mエンティティ,
    Mエンティティ識別子,
    M不変エンティティ,
    M可変エンティティ,
    MParameter,
    MOptions,
    M結果,
}

impl 設計解釈マーカー {
    /// データの役割の軸(`M不変データ` を除く。`M不変データ` はデータの役割の一種でなく、複数のデータの役割が共有する基底の契約である)。正規形・別名・再公開・波括弧付きのモジュールの検査の対象である。
    pub const fn データの役割一覧() -> [Self; 10] {
        [
            Self::M遷移が受け取る命令,
            Self::Mコマンド,
            Self::M命令の組,
            Self::Mイベント,
            Self::M規則,
            Self::M状態,
            Self::M解釈前の入力,
            Self::M生入力,
            Self::M中間入力,
            Self::M観測,
        ]
    }

    /// 処理の役割の軸。`M工程` はデータの役割に含めない。`M不変データ` を上位トレイトに持たないため純粋データ規約の対象にせず、正規形・別名・再公開・波括弧付きのモジュールの検査の対象にはする。
    /// 同じ層に属する関数の役割(`M射影関数`・`M解釈関数`・`M遷移関数` など。全部は `_doc/設計/設計オントロジー.md` 第3節が並べる)は境界付きの newtype であってトレイトのマーカーではないため、この一覧に現れない。
    pub const fn 処理の役割一覧() -> [Self; 1] {
        [Self::M工程]
    }

    /// `M不変データ` を上位トレイトに持つデータの役割。これらを実装する型の定義にも純粋データ規約を当てる(`impl M不変データ for` の置き場所は問わない)。
    /// 検査器が型の定義をたどる必要があるのはこの一覧と `M不変データ` と `MParameter` と `M結果`(正本の標準の `Result` への包括の実装を除く)だけである。
    /// データの役割はどれも `M不変データ` を上位トレイトに持つ(下位の分類は上位の分類を通して持つ)ため、この一覧はデータの役割の一覧と同じである。
    pub const fn 純粋データの役割一覧() -> [Self; 10] {
        Self::データの役割一覧()
    }

    /// 存在の分類の軸。純粋データ規約の対象にはしない(`Mエンティティ` は `M不変データ` を要求しないため)。`M不変データ` を上位トレイトに持つものは `impl M不変データ for` の行を通して検査される。
    pub const fn 存在の分類一覧() -> [Self; 3] {
        [Self::M値オブジェクト, Self::Mエンティティ, Self::Mエンティティ識別子]
    }

    /// 変更可能性の軸(エンティティの不変と可変)。同じ型が両方を名乗ることは `排他の分類を同時に名乗っていないこと` が違反にする。
    pub const fn 変更可能性一覧() -> [Self; 2] {
        [Self::M不変エンティティ, Self::M可変エンティティ]
    }

    /// 関数境界の役割の軸。`MParameter` と `MOptions` は `M不変データ` を上位トレイトに持つため、純粋データ規約は `impl M不変データ for` の行を通して掛かる。
    /// `MParameter` には加えて `Option<` のフィールドを持たないことを課す(`parameter_assertion.rs`)。同じ型が両方を名乗ることは `排他の分類を同時に名乗っていないこと` が違反にする。
    /// `M結果` は上位トレイトを持たず、純粋データ規約を課さない(`純粋データの役割一覧` に入れない)。結果は判別型であるという構文の法則として、実装の対象の型が `enum` であることだけを課す(`すべての結果が列挙型であること`。正本 `blitz_design` が持つ標準の `Result` への包括の実装だけが定義をたどらない特例である)。
    pub const fn 関数境界の役割一覧() -> [Self; 3] {
        [Self::MParameter, Self::MOptions, Self::M結果]
    }

    /// 純粋データ規約(参照・生ポインタ・内部可変性を持たず、指し先は共有される不変データを指す `Arc` だけ)を当てる基底の契約。
    /// 値を複製して渡す `M不変データ` と、1つの実体を共有して読む `M共有される不変データ` の2つであり、どちらも中身が変わらない純粋な所有データである。
    pub const fn 基底の契約一覧() -> [Self; 2] {
        [Self::M不変データ, Self::M共有される不変データ]
    }

    /// 実装の正規形と再公開の禁止の対象になる全部のマーカー。2つの基底の契約と5つの軸を連ねる。
    pub fn 全部の一覧() -> Vec<Self> {
        Self::基底の契約一覧()
            .into_iter()
            .chain(Self::データの役割一覧())
            .chain(Self::処理の役割一覧())
            .chain(Self::存在の分類一覧())
            .chain(Self::変更可能性一覧())
            .chain(Self::関数境界の役割一覧())
            .collect()
    }

    pub const fn 名前(self) -> &'static str {
        match self {
            Self::M不変データ => "M不変データ",
            Self::M共有される不変データ => "M共有される不変データ",
            Self::M遷移が受け取る命令 => "M遷移が受け取る命令",
            Self::Mコマンド => "Mコマンド",
            Self::M命令の組 => "M命令の組",
            Self::Mイベント => "Mイベント",
            Self::M規則 => "M規則",
            Self::M状態 => "M状態",
            Self::M解釈前の入力 => "M解釈前の入力",
            Self::M生入力 => "M生入力",
            Self::M中間入力 => "M中間入力",
            Self::M観測 => "M観測",
            Self::M工程 => "M工程",
            Self::M値オブジェクト => "M値オブジェクト",
            Self::Mエンティティ => "Mエンティティ",
            Self::Mエンティティ識別子 => "Mエンティティ識別子",
            Self::M不変エンティティ => "M不変エンティティ",
            Self::M可変エンティティ => "M可変エンティティ",
            Self::MParameter => "MParameter",
            Self::MOptions => "MOptions",
            Self::M結果 => "M結果",
        }
    }
}
