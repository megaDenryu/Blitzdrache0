//! `クレート構文検査` の説明関数のうち、分類の排他と網羅を検査するもの。排他の分類(同じ軸の組と、軸をまたぐ1つの組)を同じ型が同時に名乗っていないことと、
//! 下位の分類で分ける上位の分類を名乗る型が下位の分類のどれかを名乗っていることの2つであり、2つが揃って「下位の分類のちょうど1つを名乗る」を言う。
//! 排他の組は `排他の分類の組一覧` が持つ(2つの基底の契約の `M不変データ` と `M共有される不変データ`、`M不変エンティティ` と `M可変エンティティ`、`MParameter` と `MOptions`、`M生入力` と `M中間入力`、`Mコマンド` と `M命令の組`、軸をまたぐ `M命令の組` と `MParameter`)。
//! 上位と下位の組は `上位の分類と下位の分類の組一覧` が持つ(`M解釈前の入力` を `M生入力` と `M中間入力` で、`M状態遷移が受け取る命令` を `Mコマンド` と `M命令の組` で分ける)。
//! どちらも型の同一性(推定したモジュールパス + 型名)で実装を集めて突き合わせる。排他は両方にある型を後の方の実装の行で、網羅は下位のどれにも無い型を上位の実装の行で違反にする。

use std::collections::{HashMap, HashSet};

use super::module_path::モジュールパス;
use super::syntax_checker::クレート構文検査;
use super::trait_implementation::設計解釈マーカーの実装;
use super::設計解釈マーカーの一覧::設計解釈マーカー;

/// 排他の分類の組。同じ型が組の両方を名乗ることは意味として同時に成り立たない。最初の組は2つの基底の契約であり(値を複製して渡すか、1つの実体を共有して読むか)、
/// 最後の組だけは軸をまたぐ(`Mコマンド` だけを並べた構造体は `MParameter` でなく `M命令の組` を名乗る)。
const 排他の分類の組一覧: [(設計解釈マーカー, 設計解釈マーカー); 6] = [
    (設計解釈マーカー::M不変データ, 設計解釈マーカー::M共有される不変データ),
    (設計解釈マーカー::M不変エンティティ, 設計解釈マーカー::M可変エンティティ),
    (設計解釈マーカー::MParameter, 設計解釈マーカー::MOptions),
    (設計解釈マーカー::M生入力, 設計解釈マーカー::M中間入力),
    (設計解釈マーカー::Mコマンド, 設計解釈マーカー::M命令の組),
    (設計解釈マーカー::M命令の組, 設計解釈マーカー::MParameter),
];

/// 上位の分類と、それを分ける下位の分類の組。上位の分類を名乗る型は、組の下位の分類のどちらか1つもあわせて名乗る(両方を名乗らないことは `排他の分類の組一覧` が受け持つ)。
/// `M解釈前の入力` を `M生入力` と `M中間入力` で、`M状態遷移が受け取る命令` を `Mコマンド`(選択肢を数え上げた列挙)と `M命令の組`(`Mコマンド` だけを名前付きのフィールドに並べた構造体)で分ける。
const 上位の分類と下位の分類の組一覧: [(設計解釈マーカー, [設計解釈マーカー; 2]); 2] = [
    (設計解釈マーカー::M解釈前の入力, [設計解釈マーカー::M生入力, 設計解釈マーカー::M中間入力]),
    (設計解釈マーカー::M状態遷移が受け取る命令, [設計解釈マーカー::Mコマンド, 設計解釈マーカー::M命令の組]),
];

impl クレート構文検査 {
    /// 同じ型が排他の分類の組の両方を名乗っていないこと。不変と可変は意味として同時に成り立たず、必須の束と任意の束は引数オブジェクトの軸の排他の分類である。
    /// `Mコマンド` だけを並べた構造体は、関数へ渡す必須入力の束(`MParameter`)でなく命令の組(`M命令の組`)を名乗る。
    pub fn 排他の分類を同時に名乗っていないこと(mut self) -> Self {
        for (甲, 乙) in 排他の分類の組一覧 {
            let 甲の一覧: HashMap<(モジュールパス, String), 設計解釈マーカーの実装> = self.設計解釈マーカーの実装一覧(甲).into_iter().map(|型| (self.型の同一性(&型), 型)).collect();
            for 乙の型 in self.設計解釈マーカーの実装一覧(乙) {
                if 甲の一覧.contains_key(&self.型の同一性(&乙の型)) {
                    self.違反にする(&乙の型, 排他の違反の説明(甲));
                }
            }
        }
        self
    }

    /// 下位の分類で分ける上位の分類を名乗る型が、下位の分類のどれかを名乗っていること。`M解釈前の入力` は出どころに固有の形の値か、出どころに依らない形へ整えた値かのどちらかであり、どちらでもない解釈前の入力は無い。
    /// `M状態遷移が受け取る命令` は1つの選択(`Mコマンド`)か、`Mコマンド` だけを名前付きのフィールドに並べた構造体(`M命令の組`)のどちらかであり、どちらでもない命令は無い。
    pub fn 上位の分類を名乗る型が下位の分類のどれかを名乗っていること(mut self) -> Self {
        for (上位, 下位一覧) in 上位の分類と下位の分類の組一覧 {
            let 下位を名乗る型: HashSet<(モジュールパス, String)> = 下位一覧.into_iter().flat_map(|下位| self.設計解釈マーカーの実装一覧(下位)).map(|型| self.型の同一性(&型)).collect();
            for 上位の型 in self.設計解釈マーカーの実装一覧(上位) {
                if !下位を名乗る型.contains(&self.型の同一性(&上位の型)) {
                    self.違反にする(&上位の型, 網羅の違反の説明(下位一覧));
                }
            }
        }
        self
    }
}

fn 網羅の違反の説明(下位一覧: [設計解釈マーカー; 2]) -> String {
    let [甲, 乙] = 下位一覧;
    format!("は `{}` と `{}` のどちらも名乗っていない。この分類は下位の分類のどちらか1つを必ずあわせて名乗る", 甲.名前(), 乙.名前())
}

fn 排他の違反の説明(甲: 設計解釈マーカー) -> String {
    format!("は `{}` も名乗っている。排他の分類であり同時には成り立たないため、どちらか一方だけを名乗る({})", 甲.名前(), 排他の理由(甲))
}

fn 排他の理由(甲: 設計解釈マーカー) -> &'static str {
    match 甲 {
        設計解釈マーカー::M不変データ => "値を複製して渡す不変データと、複製せず1つの実体を共有して読む共有される不変データは、渡し方で分かれる2つの基底の契約であり、同じ値が両方の渡し方を名乗ることはできない",
        設計解釈マーカー::M不変エンティティ => "自己変更を禁じる不変エンティティと、同一性を保ったまま内部の状態を更新する可変エンティティは、意味として同時に成り立たない",
        設計解釈マーカー::MParameter => "必須入力の束と任意の設定の束は、関数境界の役割の軸の排他の分類である",
        設計解釈マーカー::M生入力 => "入力の出どころに固有の形のままの生入力と、出どころに依らない形へ整えた中間入力は、解釈前の入力の排他の分類である",
        設計解釈マーカー::Mコマンド => "選択肢を数え上げた列挙であるコマンドと、コマンドだけを名前付きのフィールドに並べた構造体である命令の組は、状態遷移が受け取る命令の排他の分類である",
        設計解釈マーカー::M命令の組 => "軸をまたぐ排他である。命令の組は状態遷移のコマンドの位置へ入れる命令であり、必須入力の束(`MParameter`)はコマンドの位置へ入れない引数であるため、定義から同時には成り立たない",
        _ => "同じ軸の排他の分類である",
    }
}
