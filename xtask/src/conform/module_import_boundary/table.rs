//! 取り込みを閉じるモジュールの台帳。担当するのは「どのモジュールを、どのファイルだけが取り込んでよいか」の
//! 並びだけである。検査の手順は親モジュールが持つ。
//!
//! 台帳を分けるのは、境界を1つ増やすときに触るのがこの並び1つになるようにするためである。

/// 取り込みを閉じる1つのモジュールと、それを取り込んでよいファイルの並び。
pub(super) struct 取り込みの境界 {
    pub(super) モジュール名: &'static str,                          // `import`で書かれるモジュール名(拡張子なし)
    pub(super) 取り込んでよいファイル一覧: &'static [&'static str], // 区切りはスラッシュで書く
    pub(super) 再輸出を許すか: bool,                                // 許さないモジュールは、取り込んでよいファイルでも再輸出できない
    pub(super) 閉じる理由: &'static str,                            // 違反のときに並べる、閉じている理由の一文
}

/// 局所光とクラスタの内側を材質のシェーダーから閉じる2つの境界。
///
/// 束縛先の`local_light_binding`は再輸出を許さない。局所光の問い合わせがこれを再輸出した瞬間、問い合わせを
/// 取り込んだ材質のシェーダーへ資源の名前がそのまま漏れるためである。型の`local_light_records`は再輸出を許す。
/// 再輸出する先が`local_light_binding`であり、そちらが取り込みを閉じられているためである。
pub(super) const 境界一覧: [取り込みの境界; 2] = [
    取り込みの境界 {
        モジュール名: "local_light_binding",
        取り込んでよいファイル一覧: &["shaders/local_light_shading.slang"],
        再輸出を許すか: false,
        閉じる理由: "材質のシェーダーが光源の並びとクラスタの生成方法を知らないという先行裁定を、名前が見えないことで守るためである。局所光は局所光の問い合わせ(shaders/local_light_shading.slang)を通して読む",
    },
    取り込みの境界 {
        モジュール名: "local_light_records",
        取り込んでよいファイル一覧: &["shaders/local_light_binding.slang", "shaders/cluster_light_assignment.slang"],
        再輸出を許すか: true,
        閉じる理由: "束縛先を閉じても型の名前が見えれば、材質のシェーダーがレコードの並びを前提にした式を書けてしまうためである",
    },
];
