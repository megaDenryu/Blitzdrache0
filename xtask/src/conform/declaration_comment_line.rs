//! 宣言の並びの検査: 構造体・列挙の宣言ブロックの中に、コメントだけの行が無いことを確かめる。
//!
//! 名前と型が縦に揃っていること自体が読みやすさの源であり、宣言と宣言の間へコメントの行が入ると
//! 読み手は宣言を目で拾い直すことになる。説明は宣言と同じ行の末尾へ書く。
//!
//! 例外は`///`の説明の注釈である。Rustは説明の注釈の位置を宣言の前に固定しており行末へ書けないため、
//! 1つの宣言につき1行だけ許す。2行以上積まれたものは違反として報告する。
//! 参照: グローバルCLAUDE.md「コメント」の2026-08-27の裁定、CLAUDE.md「コメント」。

use std::path::Path;

use super::source_lexing::{コードだけの行一覧, 行ごとの内訳, 行の内訳};
use super::violation::違反;

pub fn 検査する(パス: &Path, 内容: &str) -> Vec<違反> {
    let 内訳一覧 = 行ごとの内訳(内容);
    let コード行一覧 = コードだけの行一覧(内容);
    let mut 違反一覧 = Vec::new();
    let mut 深さ = 0usize;
    for (添字, コード行) in コード行一覧.iter().enumerate() {
        if 深さ == 0 {
            if 宣言ブロックの開きか(コード行) {
                深さ = 1;
            }
            continue;
        }
        深さ = (深さ + コード行.matches('{').count()).saturating_sub(コード行.matches('}').count());
        if 深さ == 0 {
            continue;
        }
        if !宣言の前に置かれたコメントの行か(&内訳一覧, &コード行一覧, 添字) {
            continue;
        }
        if let Some(文言) = 宣言の前のコメントの違反の文言を求める(&内訳一覧, 添字) {
            違反一覧.push(違反::行単位(パス.to_path_buf(), 添字 + 1, 文言));
        }
    }
    違反一覧
}

/// 宣言の前へ置かれたコメントの行が違反かを判定し、違反なら報告の文言を返す。
/// `///`の説明の注釈は行末へ書けないため1行だけ許し、同じ宣言へ2行目が積まれたところから違反にする。
fn 宣言の前のコメントの違反の文言を求める(内訳一覧: &[行の内訳], 添字: usize) -> Option<String> {
    if !内訳一覧.get(添字).is_some_and(行の内訳::説明の注釈だけの行か) {
        return Some("宣言の間にコメントだけの行が在る。説明は宣言と同じ行の末尾へ書く".to_string());
    }
    let 直前も説明の注釈 = 添字
        .checked_sub(1)
        .and_then(|前の添字| 内訳一覧.get(前の添字))
        .is_some_and(行の内訳::説明の注釈だけの行か);
    直前も説明の注釈.then(|| "1つの宣言へ説明の注釈が2行以上積まれている。1行へ収めるか、説明を型自身の注釈へ移す".to_string())
}

/// 構造体・列挙の宣言が波括弧を開く行かを判定する。タプル構造体と型別名は波括弧を持たないため掛からない。
fn 宣言ブロックの開きか(コード行: &str) -> bool {
    let 綴り = コード行.trim_start();
    let 綴り = 綴り
        .strip_prefix("pub")
        .map_or(綴り, |残り| 残り.trim_start_matches(|文字| 文字 != ' ').trim_start());
    (綴り.starts_with("struct ") || 綴り.starts_with("enum ")) && コード行.trim_end().ends_with('{')
}

/// コメントだけの行のうち、直後に宣言が続くものを判定の対象とする。直後が空行や閉じ括弧のものは宣言の並びを割らない。
fn 宣言の前に置かれたコメントの行か(内訳一覧: &[行の内訳], コード行一覧: &[String], 添字: usize) -> bool {
    if !内訳一覧.get(添字).is_some_and(行の内訳::コメントだけの行か) {
        return false;
    }
    let mut 次 = 添字 + 1;
    while 内訳一覧.get(次).is_some_and(行の内訳::コメントだけの行か) {
        次 += 1;
    }
    コード行一覧.get(次).is_some_and(|行| !行.trim().is_empty() && 行.trim() != "}")
}

