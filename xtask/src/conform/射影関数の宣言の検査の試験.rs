//! 射影関数の宣言の検査の試験。射影の型が入力の状態をそのまま、または包みの中に持つ宣言を違反にし、別の値を取り出す射影関数を違反にしないことを固定する。

use super::射影関数の宣言の検査::抽出したものを検査する;
use crate::設計関係のモデル::原文から設計関係グラフと抽出の欠けを組む;

const 型と関数: &str = "pub struct 状態 {\n    番号: u8,\n}\n\nimpl M状態 for 状態 {}\n\npub struct 表示 {\n    番号: u8,\n}\n\nimpl 状態 {\n    pub fn 写す(&self) -> 状態 {\n        todo!()\n    }\n\n    pub fn 見せる(&self) -> 表示 {\n        todo!()\n    }\n\n    pub fn 並べる(&self) -> Vec<状態> {\n        todo!()\n    }\n}\n\n";

// 型と関数の後ろへ宣言を並べた原文を検査し、違反の行番号を並べる。
fn 違反の行番号一覧(宣言一覧: &str) -> Vec<Option<usize>> {
    let 原文 = format!("{型と関数}{宣言一覧}");
    let 抽出したもの = 原文から設計関係グラフと抽出の欠けを組む(&[("crates/blitz_game/src/試験.rs", 原文.as_str())]);
    抽出したものを検査する(&抽出したもの).into_iter().map(|違反| 違反.行番号).collect()
}

// 反証: 射影関数の型引数に同じ状態を置いた宣言を通すと、定義の式が状態を変換用の素材にしかつ生成すると導き、状態遷移を宣言しないまま状態の存在理由の公理と宣言の法則を通す。
#[test]
fn 入力と出力が同じ状態の射影関数の宣言は違反になる() {
    let 行番号一覧 = 違反の行番号一覧("const _: M射影関数<状態, 状態> = M射影関数::生成する(状態::写す);\n");
    assert_eq!(行番号一覧, vec![Some(型と関数.lines().count() + 1)]);
}

// 反証: 射影の型の表記を書いたままで比べると、射影の型が状態を包みの中に持つ宣言を見落とす。
#[test]
fn 射影の型が状態を包みの中に持つ射影関数の宣言は違反になる() {
    let 行番号一覧 = 違反の行番号一覧("const _: M射影関数<状態, Vec<状態>> = M射影関数::生成する(状態::並べる);\n");
    assert_eq!(行番号一覧, vec![Some(型と関数.lines().count() + 1)]);
}

#[test]
fn 状態から別の値を取り出す射影関数の宣言は違反にならない() {
    assert!(違反の行番号一覧("const _: M射影関数<状態, 表示> = M射影関数::生成する(状態::見せる);\n").is_empty());
}
