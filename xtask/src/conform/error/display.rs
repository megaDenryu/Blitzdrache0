//! 規約検査の破れを人が読む1文へ写す。呼ばれるのは検査の入口が終了コードへ写す1箇所だけである。
//! 枝の定義と分けるのは、枝を足す変更と文面を直す変更が別々に起きるためである。

use super::規約検査の破れ;

impl std::fmt::Display for 規約検査の破れ {
    fn fmt(&self, 書き手: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::検査対象のファイルを読めなかった { パス, 誤り } => {
                write!(書き手, "{}の読み取りに失敗した: {誤り}", パス.display())
            }
            Self::検査対象のディレクトリを読めなかった { ディレクトリ, 誤り } => {
                write!(書き手, "{}の読み取りに失敗した: {誤り}", ディレクトリ.display())
            }
            Self::検査対象のファイルを走査できなかった(破れ) => write!(書き手, "検査対象のファイルを走査できなかった: {破れ}"),
            Self::型の計測を実行できなかった(破れ) => write!(書き手, "型の計測を実行できなかった: {破れ}"),
            Self::定数の宣言が無い { パス, 前置き } => write!(書き手, "{パス}に「{前置き}」で始まる行が無い"),
            Self::定数の値を数として読めない {
                パス, 前置き, 綴り, 誤り
            } => {
                write!(書き手, "{パス}の「{前置き}」の値を数として読めない: {綴り}({誤り})")
            }
            Self::束縛番号を読めない { パス, 前置き } => write!(書き手, "{パス}の「{前置き}」から束縛番号を読めない"),
            Self::束縛の属性が無い { パス, 変数名 } => write!(書き手, "{パス}に{変数名}の宣言と束縛の属性の組が無い"),
            Self::見本の宣言が無い { パス, 宣言名 } => write!(書き手, "{パス}に「{宣言名}」の宣言が無い"),
            Self::見本の宣言に等号が無い { パス, 宣言名 } => write!(書き手, "{パス}の「{宣言名}」に等号が無い"),
            Self::見本の宣言が閉じていない { パス, 宣言名 } => write!(書き手, "{パス}の「{宣言名}」が`];`で終わっていない"),
            Self::見本の宣言の値を数として読めない {
                パス, 宣言名, 綴り, 誤り
            } => {
                write!(書き手, "{パス}の「{宣言名}」の値を数として読めない: {綴り}({誤り})")
            }
            Self::見本の宣言に値が1つも無い { パス, 宣言名 } => write!(書き手, "{パス}の「{宣言名}」に値が1つも無い"),
        }
    }
}
