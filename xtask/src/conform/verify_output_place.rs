//! 検証の出力が載る木を指す綴りが、その木を名乗る型の外に現れていないかの検査。
//! 受け取るのは無し、返すのは木を指す綴りを書いたファイルの違反一覧である。
//!
//! 木の名前を入口ごとに書くと、置き場を移すときに触り漏らした入口だけが古い場所へ書き続ける。しかも綴りが
//! 合っている限りどちらも動くため、散らばりが増えても誰も困らないまま増え続ける。ここが機械的に止める。
//!
//! 見る範囲は`xtask/src`配下の`.rs`すべてであり、試験のためのファイルも外さない。外す条件を持たないのは、
//! 試験が渡す置き場も同じ木の下にあり、木の名前を試験だけが別に書いてよい理由が無いためである。
//! 木の名前そのものは`検証の出力ルート`へ尋ねる。この検査が写しを持つと、検査の側が2つ目の綴りになる。
//! 参照: CLAUDE.md「ツールとドキュメントの配置」。

use std::path::{Path, PathBuf};

use super::error::規約検査の破れ;
use super::source_lexing;
use super::violation::違反;
use crate::file_scan;
use crate::verify::検証の出力ルート;

const 走査するディレクトリ一覧: [&str; 1] = ["xtask/src"];
const 走査する拡張子一覧: [&str; 1] = ["rs"];

/// 木の名前を綴ってよい唯一のファイル。`検証の出力ルート`を定義する場所である。
const 木の名前を綴ってよいファイル: &str = "xtask/src/verify/output/root.rs";

pub fn 全ファイルを検査する() -> Result<Vec<違反>, 規約検査の破れ> {
    let 木の名前 = 検証の出力ルート::既定().木の名前();
    let 木の下を指す接頭辞 = format!("{木の名前}/");
    let mut 違反一覧 = Vec::new();
    for パス in file_scan::対象ファイル一覧を集める(&走査するディレクトリ一覧, &走査する拡張子一覧)? {
        if 綴ってよいファイルか(&パス) {
            continue;
        }
        let 内容 = std::fs::read_to_string(&パス).map_err(|誤り| 規約検査の破れ::ファイルを読めなかった(&パス, 誤り))?;
        違反一覧.extend(ファイル1つを検査する(&パス, &内容, 木の名前, &木の下を指す接頭辞));
    }
    Ok(違反一覧)
}

fn 綴ってよいファイルか(パス: &Path) -> bool {
    パス.to_string_lossy().replace('\\', "/") == 木の名前を綴ってよいファイル
}

fn ファイル1つを検査する(パス: &Path, 内容: &str, 木の名前: &str, 木の下を指す接頭辞: &str) -> Vec<違反> {
    source_lexing::字句へ分ける(内容)
        .iter()
        .filter(|断片| 断片.区分 == source_lexing::字句の区分::文字列リテラル)
        .filter(|断片| 断片.中身 == 木の名前 || 断片.中身.starts_with(木の下を指す接頭辞))
        .map(|断片| 木を指す綴りの違反(パス, 断片.開始行, &断片.中身))
        .collect()
}

fn 木を指す綴りの違反(パス: &Path, 行番号: usize, 綴り: &str) -> 違反 {
    違反::行単位(
        PathBuf::from(パス),
        行番号,
        format!(
            "検証の出力が載る木を指す綴り「{綴り}」がここに在る(置き場の名前だけを宣言し、パスは検証の出力ルートのメソッドから導く。木の名前を綴ってよいのは{木の名前を綴ってよいファイル}だけである)"
        ),
    )
}
