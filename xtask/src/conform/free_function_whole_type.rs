//! 親の型を丸ごと受け取る自由関数の検査。受け取るのは無し、返すのは違反一覧か、走査を実行できなかった理由である。
//!
//! 切り出した先が親の型を丸ごと(`&親型`・`&mut 親型`)受け取るなら、それは工程の分離ではなく親の中身を別ファイルへ
//! 置いただけであり、親のフィールドを1つも減らさない。行数の検査も切り出しの根拠義務の条文も、この形を止められない。
//! 参照: CLAUDE.md「切り出しの根拠義務(パーシャル規約)」の2026-09-04の追記。
//!
//! 親とみなすのは、その関数のファイルを子孫に持つモジュールで定義された型だけである。同じクレートの離れた
//! モジュールの型を対等な引数として受け取る純粋な計算は、規約が自由関数を許す形そのものであるため落とす。
//! 検出の取りこぼしを許して誤検出を出さない側へ倒しており、次の形は検出しない。波括弧の深さ0に無い関数
//! (implのメソッド・トレイトの宣言・`mod`の中の関数)、マクロが生成する関数、型引数で受け取る形、
//! スライス・タプル・トレイトの対象・入れ物ごしの参照、試験と例のためのファイルの中の関数である。
//! 見出しで認めたGraphiteの生成物は手で編集できないため、型ごとの分量の台帳の検査と同じく観測から外し、外した件数と名前を報告する(Issue #187)。

