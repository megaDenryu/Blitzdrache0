/// Graphiteの生成物から外す検査の名前。報告の行がこの名前で外した検査を名乗る。
const 生成物から外す検査: &str = "親の型を丸ごと受け取る自由関数";

pub fn 全ファイルの自由関数を検査する() -> Result<検査の報告, 規約検査の破れ> {
    let 観測 = 生成物を除いた観測::走査対象から集める()?;
    let 索引 = 型の定義の索引::観測から生成する(&観測.観測一覧);
    let mut 検出一覧 = Vec::new();
    for パス in 観測.観測一覧.iter().map(|ファイル| &ファイル.パス).filter(|パス| !試験のためのファイルか(パス)) {
        let 内容 = std::fs::read_to_string(パス).map_err(|誤り| 規約検査の破れ::ファイルを読めなかった(パス, 誤り))?;
        検出一覧.extend(索引.親の型を丸ごと受け取る自由関数を探す(パス, &内容));
    }
    let 外した生成物 = 対象外にした生成物::生成する(生成物から外す検査, 観測.除いた生成物一覧);
    Ok(検査の報告::生成する(ledger::台帳と照合する(&検出一覧), Vec::new()).対象外にした生成物を足す(外した生成物))
}
