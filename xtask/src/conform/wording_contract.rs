//! アプリが出す行の綴りと、それを読む検収の綴りの突き合わせ。
//! 受け取るのは無し(対象の綴りは表が持つ)、返すのは綴りが消えたファイルの違反一覧である。
//!
//! アプリの標準出力は検収との機械の契約であり、綴りが1文字違うと検収は行を見つけられない。
//! 見つからないときの失敗はその場では「値が無い」としか出ず、どちらの側を直せばよいか読み手には分からない。
//! 台帳が契約の綴りを1つ持ち、その綴りが現れるべきファイルを列挙することで、片側だけの書き換えを検査が拒む。
//!
//! 綴りが文字列リテラルの中に在ることまで見るのは、コメントでの言及を出現として数えないためである。

mod table;
#[cfg(test)]
mod tests;

use std::path::{Path, PathBuf};

use super::violation::違反;

pub fn 全綴りを検査する() -> Result<Vec<違反>, String> {
    let mut 違反一覧 = Vec::new();
    for 契約 in table::領域一覧.iter().copied().flatten() {
        for パス in 契約.現れるファイル一覧 {
            let 内容 = std::fs::read_to_string(Path::new(パス)).map_err(|誤り| format!("{パス}の読み取りに失敗した: {誤り}"))?;
            if !内容.lines().any(|行| 文字列リテラルの中に現れるか(行, 契約.綴り)) {
                違反一覧.push(違反::ファイル単位(
                    PathBuf::from(*パス),
                    format!(
                        "契約した綴り「{}」が文字列リテラルとして無い(この綴りを変えるなら{}の全部とconformの台帳を同時に直す)",
                        契約.綴り,
                        契約.現れるファイル一覧.join("・")
                    ),
                ));
            }
        }
    }
    Ok(違反一覧)
}

/// その行で綴りが二重引用符に挟まれているか。最初の出現だけを見るのは、同じ行に綴りの言及と
/// リテラルが同居する書き方をこの台帳の対象が持たないためである。挟まれていない出現しか無ければ
/// 違反として報告し、人が書き方を直すか台帳を直す。
fn 文字列リテラルの中に現れるか(行: &str, 綴り: &str) -> bool {
    let Some(位置) = 行.find(綴り) else {
        return false;
    };
    行[..位置].contains('"') && 行[位置 + 綴り.len()..].contains('"')
}
