//! 束縛番号の正本(CPU側の定数)と、シェーダーの宣言に付いた束縛の属性の突き合わせ。
//! 受け取るのは無し(対象の組は表が持つ)、返すのは番号かセット番号が食い違った組の違反一覧である。
//!
//! 束縛番号はCPUとシェーダーが別々に書き、両者を結ぶものはコメントしかない。片方だけを動かすと
//! ディスクリプタの書き込み先と読み手がずれるが、ずれた先に型の合う別の資源が結ばれていれば検証層も黙り、
//! 絵の破綻としてしか現れない。ここが機械的に見る。
//!
//! 値の写しの検査と別の台帳を立てるのは、読み取りの規則が別物だからである。値は宣言の前置きの後ろに来るが、
//! 束縛の属性は識別子より前に来るため、前置きを取り除いた残りを数として読む規則では取り出せない。

mod master_number;
mod shader_attribute;
mod table;

use std::path::PathBuf;

use super::error::規約検査の破れ;
use super::violation::違反;
use table::束縛番号の組;

pub fn 全束縛番号を検査する() -> Result<Vec<違反>, 規約検査の破れ> {
    let mut 違反一覧 = Vec::new();
    for 組 in table::領域ごとの台帳の一覧.iter().copied().flatten() {
        違反一覧.extend(組1つを検査する(組)?);
    }
    Ok(違反一覧)
}

fn 組1つを検査する(組: &束縛番号の組) -> Result<Vec<違反>, 規約検査の破れ> {
    let 正本の番号 = master_number::正本の束縛番号を読む(組.正本パス, 組.正本の前置き)?;
    let 属性 = shader_attribute::写しの束縛の属性を読む(組.写しパス, 組.写しの変数名)?;
    let mut 違反一覧 = Vec::new();
    if 属性.番号 != 正本の番号 {
        違反一覧.push(違反::ファイル単位(
            PathBuf::from(組.写しパス),
            format!(
                "{}の束縛番号が正本と食い違う(正本{正本の番号}・写し{}・正本は{})",
                組.写しの変数名, 属性.番号, 組.正本パス
            ),
        ));
    }
    if 属性.セット番号 != 組.セット番号 {
        違反一覧.push(違反::ファイル単位(
            PathBuf::from(組.写しパス),
            format!(
                "{}のセット番号が台帳と食い違う(台帳{}・写し{})",
                組.写しの変数名, 組.セット番号, 属性.セット番号
            ),
        ));
    }
    Ok(違反一覧)
}
