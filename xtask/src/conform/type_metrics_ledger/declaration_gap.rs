//! 宣言の分量について、計測と台帳の上限の食い違いを1文へ写す。件数の比較の前に種別の一致を見る。
//!
//! 構造体のフィールド数と列挙の枝数は別の指標であり、同じ数でも意味が違う。型を構造体から列挙へ
//! 作り替えたのに台帳の行がそのままだと、件数がたまたま一致するかぎり検査が黙って通ってしまう。

use crate::type_metrics::宣言の分量;

use super::amount::指標の食い違い;

pub fn 宣言の食い違い(計測: Option<&宣言の分量>, 上限: &宣言の分量) -> Option<String> {
    let Some(計測) = 計測 else {
        return Some(format!("{}を数える宣言が走査に現れない(型の定義行を走査範囲に置く)", 上限.指標名()));
    };
    if !計測.同じ種別か(上限) {
        return Some(format!("宣言の種別が{}から{}へ変わった", 上限.指標名(), 計測.指標名()));
    }
    指標の食い違い(計測.指標名(), 計測.件数(), 上限.件数())
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn 種別が違えば件数が同じでも食い違いにする() {
        let 説明 = 宣言の食い違い(Some(&宣言の分量::列挙の枝数(3)), &宣言の分量::構造体のフィールド数(3));
        assert!(説明.is_some_and(|説明| 説明.contains("種別が")));
    }

    #[test]
    fn 同じ種別なら件数だけを比べる() {
        assert!(宣言の食い違い(Some(&宣言の分量::列挙の枝数(3)), &宣言の分量::列挙の枝数(3)).is_none());
        let 説明 = 宣言の食い違い(Some(&宣言の分量::列挙の枝数(4)), &宣言の分量::列挙の枝数(3));
        assert!(説明.is_some_and(|説明| 説明.contains("枝数が3から4へ増えた")));
    }

    #[test]
    fn 宣言が走査に現れなければ食い違いにする() {
        assert!(宣言の食い違い(None, &宣言の分量::構造体のフィールド数(3)).is_some());
    }
}
