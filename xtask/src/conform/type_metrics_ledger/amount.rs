//! 1つの型について計測した分量と、その分量が閾値と台帳の上限に対してどう位置するかの判定。
//! 分量そのものが判定を持つのは、3つの指標を呼び出し側でばらして比べさせないためである。

use crate::type_metrics::型計測;

use super::limit::型ごとの上限;

/// 台帳への登録が要るかを分ける線。この線を超えた型だけを台帳へ載せる。全型を載せると台帳が
/// リポジトリの型の一覧になり、通常の実装のたびに無関係な更新を強いることになる。
pub const 実装ファイル数の閾値: usize = 5;
pub const フィールド数の閾値: usize = 10;
pub const メソッド総数の閾値: usize = 15;

pub struct 型の分量 {
    実装ファイル数: usize,
    フィールド数: usize,
    メソッド総数: usize,
}

impl 型の分量 {
    pub fn 計測から生成する(計測: &型計測) -> Self {
        Self {
            実装ファイル数: 計測.実装ファイル一覧.len(),
            フィールド数: 計測.フィールド数,
            メソッド総数: 計測.メソッド総数,
        }
    }

    /// 3つの指標のどれか1つでも閾値を超えていれば、その型は台帳への登録が要る。
    pub fn 閾値を超えているか(&self) -> bool {
        self.実装ファイル数 > 実装ファイル数の閾値 || self.フィールド数 > フィールド数の閾値 || self.メソッド総数 > メソッド総数の閾値
    }

    /// 台帳の上限との食い違いを1文へ写す。増えたときだけでなく減ったときも食い違いとして返し、
    /// 台帳の更新を強制する。減る方向の力を仕組みで用意しないと、是正が進んでも上限が残り続ける。
    pub fn 上限との食い違い(&self, 上限: &型ごとの上限) -> Option<String> {
        let 食い違い一覧: Vec<String> = [
            指標の食い違い("impl分散ファイル数", self.実装ファイル数, 上限.実装ファイル数),
            指標の食い違い("フィールド数", self.フィールド数, 上限.フィールド数),
            指標の食い違い("メソッド総数", self.メソッド総数, 上限.メソッド総数),
        ]
        .into_iter()
        .flatten()
        .collect();
        if 食い違い一覧.is_empty() {
            return None;
        }
        Some(format!("型「{}」の分量が台帳と食い違う: {}", 上限.型名, 食い違い一覧.join(" / ")))
    }

    pub fn 綴り(&self) -> String {
        format!(
            "impl分散{} / フィールド{} / メソッド{}",
            self.実装ファイル数, self.フィールド数, self.メソッド総数
        )
    }
}

fn 指標の食い違い(指標名: &str, 計測値: usize, 上限: usize) -> Option<String> {
    if 計測値 == 上限 {
        return None;
    }
    let 向き = if 計測値 > 上限 {
        "増えた"
    } else {
        "減った(台帳を更新する)"
    };
    Some(format!("{指標名}が{上限}から{計測値}へ{向き}"))
}
