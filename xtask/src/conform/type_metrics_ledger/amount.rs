//! 1つの型について計測した分量と、その分量が閾値と台帳の上限に対してどう位置するかの判定。
//! 分量そのものが判定を持つのは、3つの指標を呼び出し側でばらして比べさせないためである。

use crate::type_metrics::{型計測, 宣言の分量};

use super::declaration_gap::宣言の食い違い;
use super::limit::型ごとの上限;

/// 台帳への登録が要るかを分ける線。この線を超えた型だけを台帳へ載せる。全型を載せると台帳が
/// リポジトリの型の一覧になり、通常の実装のたびに無関係な更新を強いることになる。
pub const 実装ファイル数の閾値: usize = 5;
pub const フィールド数の閾値: usize = 10;
/// 列挙の枝はフィールドより多くなるのが普通である。破られた不変条件を1つの枝で言う型付きエラーが代表で、
/// 枝を足すこと自体は責務の集中ではない。実測では枝が10を超える列挙が43件あり、フィールドと同じ線を引くと
/// 台帳の3分の2が普通の型付きエラーで埋まる。枝の数は19と21の間が空いており、20を超えるのは9件(最大46)である。
/// この空きを線にしている。
pub const 列挙の枝数の閾値: usize = 20;
pub const メソッド総数の閾値: usize = 15;

pub struct 型の分量 {
    実装ファイル数: usize,
    宣言: Option<宣言の分量>,
    メソッド総数: usize,
}

impl 型の分量 {
    pub fn 計測から生成する(計測: &型計測) -> Self {
        Self {
            実装ファイル数: 計測.実装ファイル一覧.len(),
            宣言: 計測.宣言.as_ref().map(|宣言| 宣言.分量),
            メソッド総数: 計測.メソッド総数,
        }
    }

    /// 3つの指標のどれか1つでも閾値を超えていれば、その型は台帳への登録が要る。
    pub fn 閾値を超えているか(&self) -> bool {
        self.実装ファイル数 > 実装ファイル数の閾値 || self.メソッド総数 > メソッド総数の閾値 || self.宣言.is_some_and(宣言が閾値を超えているか)
    }

    /// 台帳の上限との食い違いを1文へ写す。増えたときだけでなく減ったときも食い違いとして返し、
    /// 台帳の更新を強制する。減る方向の力を仕組みで用意しないと、是正が進んでも上限が残り続ける。
    pub fn 上限との食い違い(&self, 上限: &型ごとの上限) -> Option<String> {
        let 食い違い一覧: Vec<String> = [
            指標の食い違い("impl分散ファイル数", self.実装ファイル数, 上限.実装ファイル数),
            宣言の食い違い(self.宣言.as_ref(), &上限.宣言の上限),
            指標の食い違い("メソッド総数", self.メソッド総数, 上限.メソッド総数),
        ]
        .into_iter()
        .flatten()
        .collect();
        if 食い違い一覧.is_empty() {
            return None;
        }
        Some(format!("型「{}」の分量が台帳と食い違う: {}", 上限.型名, 食い違い一覧.join(" / ")))
    }

    pub fn 綴り(&self) -> String {
        let 宣言の綴り = match &self.宣言 {
            Some(分量) => format!("{}{}", 分量.指標名(), 分量.件数()),
            None => "宣言なし".to_string(),
        };
        format!("impl分散{} / {宣言の綴り} / メソッド{}", self.実装ファイル数, self.メソッド総数)
    }
}

fn 宣言が閾値を超えているか(分量: 宣言の分量) -> bool {
    match 分量 {
        宣言の分量::構造体のフィールド数(件数) => 件数 > フィールド数の閾値,
        宣言の分量::列挙の枝数(件数) => 件数 > 列挙の枝数の閾値,
    }
}

pub fn 指標の食い違い(指標名: &str, 計測値: usize, 上限: usize) -> Option<String> {
    if 計測値 == 上限 {
        return None;
    }
    let 向き = if 計測値 > 上限 {
        "増えた"
    } else {
        "減った(台帳を更新する)"
    };
    Some(format!("{指標名}が{上限}から{計測値}へ{向き}"))
}
