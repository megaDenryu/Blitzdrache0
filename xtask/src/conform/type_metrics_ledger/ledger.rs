//! 閾値を超えている型の現状の分量を、上限として登録した台帳。**この一覧への追加は、閾値を超える型を
//! 新しく作ってよいという意味ではない。** 追加が要るのは既存の型が閾値を跨いだときであり、そのときは
//! 跨いだこと自体を設計の問題として扱う。減ったときは検査が食い違いとして落とすため、是正のたびに縮む。
//!
//! 1行の鍵は定義ファイルの相対パスと型名の組である。名前だけを鍵にすると、同じ名前の型が別の場所にあるとき
//! 大きい型が小さい型に隠れて検査に現れず、違反の報告が指すファイルも誤る。
//! 行そのものは`table`の区画が持ち、この型は区画をつないで引くだけである。
//! 参照: CLAUDE.md「機械的強制」の型ごとの分量の台帳、`xtask/src/conform/split_debt.rs`の台帳と陳腐化検査。

mod entry;
mod table;

pub use entry::{区画の一覧, 台帳の行};

use crate::type_metrics::型の所在;

use super::limit::型ごとの上限;

/// 全区画の行を1つへつないだ、引ける形の台帳。上限の一覧を裸の並びで持ち回らずこの型に包むのは、
/// 引く操作(所在で参照する・計測に現れない行を挙げる)が一覧そのものの操作であり、
/// 一覧を外から持参させると呼び出し側がどの一覧を渡すかを毎回決めることになるためである。
pub struct 台帳 {
    項目一覧: Vec<型ごとの上限>,
}

impl 台帳 {
    pub fn 全区画から組む() -> Self {
        Self {
            項目一覧: table::全区画().iter().flat_map(区画の一覧::上限一覧).collect(),
        }
    }

    pub fn 上限を参照する(&self, 所在: &型の所在) -> Option<&型ごとの上限> {
        self.項目一覧.iter().find(|項目| &項目.所在 == 所在)
    }

    /// 台帳へ登録した型が計測に現れなくなったときの陳腐化。型を消したか、改名したか、定義を別のファイルへ
    /// 移したのに一覧が残っている。
    pub fn 計測に現れない項目一覧(&self, 計測済みの所在: &[&型の所在]) -> Vec<&型ごとの上限> {
        self.項目一覧.iter().filter(|項目| !計測済みの所在.contains(&&項目.所在)).collect()
    }
}
