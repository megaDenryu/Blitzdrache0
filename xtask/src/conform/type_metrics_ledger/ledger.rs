pub fn 上限を参照する(型名: &str) -> Option<&'static 型ごとの上限> {
    台帳.iter().find(|項目| 項目.型名 == 型名)
}

/// 台帳へ登録した型が計測に1つも現れなくなったときの陳腐化。型を消したか改名したのに一覧が残っている。
pub fn 計測に現れない型名一覧(計測済みの型名: &[&str]) -> Vec<&'static str> {
    台帳.iter().map(|項目| 項目.型名).filter(|型名| !計測済みの型名.contains(型名)).collect()
}

