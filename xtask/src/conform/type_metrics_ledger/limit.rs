//! 台帳へ登録した1つの型の上限値。計測が返す3つの指標と同じ形を持ち、照合の相手になる。
//!
//! 型を指す鍵は定義ファイルと型名の組である。名前だけを鍵にすると、同じ名前の型が別の場所にあるとき
//! どちらの型の上限か決まらず、大きい型が小さい型に隠れて検査に現れない。
//!
//! 宣言の上限は、生成する側の名前(`構造体`か`列挙`)で種別を言う。1つの「フィールド数」の欄へ
//! 構造体のフィールド数と列挙の枝数を混ぜると、台帳の1行を読む人がその数が何の数か判断できない。

use crate::type_metrics::{型の所在, 宣言の分量};

pub struct 型ごとの上限 {
    pub 所在: 型の所在,
    pub 実装ファイル数: usize,
    pub 宣言の上限: 宣言の分量,
    pub メソッド総数: usize,
    pub 登録されている表のファイル: &'static str, // 陳腐化の違反が指す先。行が消えるべき表を1つに絞るために持つ
}
