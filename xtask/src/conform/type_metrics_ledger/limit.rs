//! 台帳へ登録した1つの型の上限値。計測が返す3つの指標と同じ形を持ち、照合の相手になる。
//!
//! 宣言の上限は、生成する側の名前(`構造体`か`列挙`)で種別を言う。1つの「フィールド数」の欄へ
//! 構造体のフィールド数と列挙の枝数を混ぜると、台帳の1行を読む人がその数が何の数か判断できない。

use crate::type_metrics::宣言の分量;

pub struct 型ごとの上限 {
    pub 型名: &'static str,
    pub 実装ファイル数: usize,
    pub 宣言の上限: 宣言の分量,
    pub メソッド総数: usize,
}

impl 型ごとの上限 {
    pub const fn 構造体(型名: &'static str, 実装ファイル数: usize, フィールド数: usize, メソッド総数: usize) -> Self {
        Self {
            型名,
            実装ファイル数,
            宣言の上限: 宣言の分量::構造体のフィールド数(フィールド数),
            メソッド総数,
        }
    }

    pub const fn 列挙(型名: &'static str, 実装ファイル数: usize, 枝数: usize, メソッド総数: usize) -> Self {
        Self {
            型名,
            実装ファイル数,
            宣言の上限: 宣言の分量::列挙の枝数(枝数),
            メソッド総数,
        }
    }
}
