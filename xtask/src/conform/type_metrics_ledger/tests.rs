//! 照合の規則の試験。閾値の線と、上限との食い違いの言い方だけを見る。台帳の中身は`ledger_tests`が見る。
//! 計測を組み立てる補助はここが持ち、`ledger_tests`も同じものを使う。

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use crate::type_metrics::{型の所在, 宣言の分量};

use super::amount::{
    フィールド数の閾値, メソッド総数の閾値, 列挙の枝数の閾値, 型の分量, 実装ファイル数の閾値
};
use super::ledger::台帳;
use super::limit::型ごとの上限;
use super::{型計測, 計測1件を照合する};

pub(super) const 既定の定義ファイル: &str = "crates/blitz_app/src/app/mod.rs";

pub(super) fn 計測(
    定義ファイル: &str, 型名: &str, 実装ファイル数: usize, 分量: 宣言の分量, メソッド総数: usize
) -> 型計測 {
    型計測 {
        所在: 型の所在::走査したファイルから生成する(Path::new(定義ファイル), 型名),
        宣言: Some(分量),
        実装ファイル一覧: (0..実装ファイル数)
            .map(|番号| PathBuf::from(format!("{番号}")))
            .collect::<BTreeSet<PathBuf>>(),
        メソッド総数,
    }
}

fn 上限を組む(実装ファイル数: usize, 宣言の上限: 宣言の分量, メソッド総数: usize) -> 型ごとの上限 {
    型ごとの上限 {
        所在: 型の所在::走査したファイルから生成する(Path::new(既定の定義ファイル), "登録済みの型"),
        実装ファイル数,
        宣言の上限,
        メソッド総数,
        登録されている表のファイル: file!(),
    }
}

fn 構造体の計測(型名: &str, 実装ファイル数: usize, フィールド数: usize, メソッド総数: usize) -> 型計測 {
    計測(
        既定の定義ファイル,
        型名,
        実装ファイル数,
        宣言の分量::構造体のフィールド数(フィールド数),
        メソッド総数,
    )
}

#[test]
fn 閾値を超えない型は台帳に無くても違反にしない() {
    let 台帳 = 台帳::全区画から組む();
    let 境界の計測 = || 構造体の計測("小さい型", 実装ファイル数の閾値, フィールド数の閾値, メソッド総数の閾値);
    assert!(!型の分量::計測から生成する(&境界の計測()).閾値を超えているか());
    assert!(計測1件を照合する(&台帳, &境界の計測()).is_empty());
}

#[test]
fn 列挙の枝は構造体のフィールドより緩い閾値で見る() {
    let 台帳 = 台帳::全区画から組む();
    let 枝数 = フィールド数の閾値 + 1;
    assert!(枝数 <= 列挙の枝数の閾値);
    let 列挙 = 計測(既定の定義ファイル, "小さい列挙", 0, 宣言の分量::列挙の枝数(枝数), 0);
    assert!(計測1件を照合する(&台帳, &列挙).is_empty());
    assert!(!計測1件を照合する(&台帳, &構造体の計測("大きい構造体", 0, 枝数, 0)).is_empty());
}

#[test]
fn 指標が1つでも閾値を超えたら台帳への登録を要求する() {
    let 台帳 = 台帳::全区画から組む();
    for 計測値 in [
        構造体の計測("未登録の型", 実装ファイル数の閾値 + 1, 0, 0),
        構造体の計測("未登録の型", 0, フィールド数の閾値 + 1, 0),
        構造体の計測("未登録の型", 0, 0, メソッド総数の閾値 + 1),
        計測(
            "crates/blitz_app/src/app/mod.rs",
            "未登録の型",
            0,
            宣言の分量::列挙の枝数(列挙の枝数の閾値 + 1),
            0,
        ),
    ] {
        assert_eq!(計測1件を照合する(&台帳, &計測値).len(), 1);
    }
}

#[test]
fn 上限より増えても減っても食い違いにする() {
    let 上限 = 上限を組む(6, 宣言の分量::構造体のフィールド数(12), 20);
    assert!(
        型の分量::計測から生成する(&構造体の計測("登録済みの型", 6, 12, 20))
            .上限との食い違い(&上限)
            .is_none()
    );
    let 増えた = 型の分量::計測から生成する(&構造体の計測("登録済みの型", 6, 13, 20)).上限との食い違い(&上限);
    assert!(増えた.is_some_and(|説明| 説明.contains("フィールド数が12から13へ増えた")));
    let 減った = 型の分量::計測から生成する(&構造体の計測("登録済みの型", 5, 12, 20)).上限との食い違い(&上限);
    assert!(減った.is_some_and(|説明| 説明.contains("台帳を更新する")));
}

#[test]
fn 構造体の上限へ列挙の計測を当てると種別の食い違いにする() {
    let 上限 = 上限を組む(0, 宣言の分量::構造体のフィールド数(12), 0);
    let 列挙の計測 = 計測(既定の定義ファイル, "登録済みの型", 0, 宣言の分量::列挙の枝数(12), 0);
    let 説明 = 型の分量::計測から生成する(&列挙の計測).上限との食い違い(&上限);
    assert!(説明.is_some_and(|説明| 説明.contains("種別が")));
}
