//! 台帳との照合の試験。台帳そのものは現状の写しであり書き換わるため、試験は照合の規則だけを見る。

use std::collections::BTreeSet;
use std::path::PathBuf;

use crate::type_metrics::{型の宣言, 宣言の分量};

use super::amount::{
    フィールド数の閾値, メソッド総数の閾値, 列挙の枝数の閾値, 型の分量, 実装ファイル数の閾値
};
use super::limit::型ごとの上限;
use super::{型計測, 計測1件を照合する};

fn 計測(型名: &str, 実装ファイル数: usize, 分量: 宣言の分量, メソッド総数: usize) -> 型計測 {
    型計測 {
        型名: 型名.to_string(),
        宣言: Some(型の宣言 {
            ファイル: PathBuf::from("crates/blitz_app/src/app/mod.rs"),
            分量,
        }),
        実装ファイル一覧: (0..実装ファイル数)
            .map(|番号| PathBuf::from(format!("{番号}")))
            .collect::<BTreeSet<PathBuf>>(),
        メソッド総数,
    }
}

fn 構造体の計測(型名: &str, 実装ファイル数: usize, フィールド数: usize, メソッド総数: usize) -> 型計測 {
    計測(型名, 実装ファイル数, 宣言の分量::構造体のフィールド数(フィールド数), メソッド総数)
}

#[test]
fn 閾値を超えない型は台帳に無くても違反にしない() {
    let 境界の計測 = || 構造体の計測("小さい型", 実装ファイル数の閾値, フィールド数の閾値, メソッド総数の閾値);
    assert!(!型の分量::計測から生成する(&境界の計測()).閾値を超えているか());
    assert!(計測1件を照合する(&境界の計測()).is_empty());
}

#[test]
fn 列挙の枝は構造体のフィールドより緩い閾値で見る() {
    let 枝数 = フィールド数の閾値 + 1;
    assert!(枝数 <= 列挙の枝数の閾値);
    let 列挙 = 計測("小さい列挙", 0, 宣言の分量::列挙の枝数(枝数), 0);
    assert!(計測1件を照合する(&列挙).is_empty());
    assert!(!計測1件を照合する(&構造体の計測("大きい構造体", 0, 枝数, 0)).is_empty());
}

#[test]
fn 指標が1つでも閾値を超えたら台帳への登録を要求する() {
    for 計測値 in [
        構造体の計測("未登録の型", 実装ファイル数の閾値 + 1, 0, 0),
        構造体の計測("未登録の型", 0, フィールド数の閾値 + 1, 0),
        構造体の計測("未登録の型", 0, 0, メソッド総数の閾値 + 1),
        計測("未登録の型", 0, 宣言の分量::列挙の枝数(列挙の枝数の閾値 + 1), 0),
    ] {
        assert_eq!(計測1件を照合する(&計測値).len(), 1);
    }
}

#[test]
fn 上限より増えても減っても食い違いにする() {
    let 上限 = 型ごとの上限::構造体("登録済みの型", 6, 12, 20);
    assert!(
        型の分量::計測から生成する(&構造体の計測("登録済みの型", 6, 12, 20))
            .上限との食い違い(&上限)
            .is_none()
    );
    let 増えた = 型の分量::計測から生成する(&構造体の計測("登録済みの型", 6, 13, 20)).上限との食い違い(&上限);
    assert!(増えた.is_some_and(|説明| 説明.contains("フィールド数が12から13へ増えた")));
    let 減った = 型の分量::計測から生成する(&構造体の計測("登録済みの型", 5, 12, 20)).上限との食い違い(&上限);
    assert!(減った.is_some_and(|説明| 説明.contains("台帳を更新する")));
}

#[test]
fn 構造体の上限へ列挙の計測を当てると種別の食い違いにする() {
    let 上限 = 型ごとの上限::構造体("登録済みの型", 0, 12, 0);
    let 説明 = 型の分量::計測から生成する(&計測("登録済みの型", 0, 宣言の分量::列挙の枝数(12), 0)).上限との食い違い(&上限);
    assert!(説明.is_some_and(|説明| 説明.contains("種別が")));
}

#[test]
fn 台帳に載っているのに計測へ現れない型を違反にする() {
    assert!(!super::ledger::計測に現れない型名一覧(&[]).is_empty());
    assert!(super::ledger::上限を参照する("アプリ").is_some());
}
