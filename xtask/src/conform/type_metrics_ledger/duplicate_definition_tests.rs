//! 同じ所在に定義行が複数ある型を照合したときの試験。`#[cfg]`で切り替わる同名の定義が同じファイルに
//! 並ぶ形を題材にし、大きい定義が小さい定義に隠れないことと、隠れようの無い形では違反にしないことを固定する。

use std::collections::BTreeSet;
use std::path::Path;

use crate::type_metrics::{型の所在, 型計測, 宣言の分量, 所在に現れた宣言一覧};

use super::amount::{フィールド数の閾値, 型の分量};
use super::ledger::台帳;
use super::tests::既定の定義ファイル;
use super::計測1件を照合する;

fn 定義が2つある計測(型名: &str, 先の分量: 宣言の分量, 後の分量: 宣言の分量) -> 型計測 {
    let mut 宣言 = 所在に現れた宣言一覧::ただ1つの定義から生成する(先の分量);
    宣言.宣言を取り込む(後の分量);
    型計測 {
        所在: 型の所在::走査したファイルから生成する(Path::new(既定の定義ファイル), 型名),
        宣言,
        実装ファイル一覧: BTreeSet::new(),
        メソッド総数: 0,
    }
}

#[test]
fn 同じ所在の小さい定義は大きい定義を閾値の線から隠さない() {
    let 大きい定義が先 = 定義が2つある計測(
        "未登録の型",
        宣言の分量::構造体のフィールド数(フィールド数の閾値 + 1),
        宣言の分量::構造体のフィールド数(1),
    );
    assert!(型の分量::計測から生成する(&大きい定義が先).閾値を超えているか());
    let 大きい定義が後 = 定義が2つある計測(
        "未登録の型",
        宣言の分量::構造体のフィールド数(1),
        宣言の分量::構造体のフィールド数(フィールド数の閾値 + 1),
    );
    assert!(型の分量::計測から生成する(&大きい定義が後).閾値を超えているか());
}

#[test]
fn 閾値を超える定義がある所在は分量を1つに決められない違反にする() {
    let 台帳 = 台帳::全区画から組む();
    let 計測値 = 定義が2つある計測(
        "未登録の型",
        宣言の分量::構造体のフィールド数(フィールド数の閾値 + 1),
        宣言の分量::構造体のフィールド数(1),
    );
    let 違反一覧 = 計測1件を照合する(&台帳, &計測値);
    assert_eq!(違反一覧.len(), 1);
    let 説明 = &違反一覧[0].説明;
    assert!(説明.contains("1つに決められない"), "説明が曖昧さを言っていない: {説明}");
    assert!(
        説明.contains(&format!("フィールド数{}", フィールド数の閾値 + 1)),
        "大きい定義が説明に無い: {説明}"
    );
}

/// `xtask/src/editor/kill_with_parent.rs`の`道連れの仕掛け`と同じ形である。`#[cfg(windows)]`の列挙と
/// `#[cfg(not(windows))]`の構造体が同じファイルに並び、どちらも小さい。比べる相手が台帳にも閾値にも
/// 無いため、種別が混ざっていても隠れる型は無い。
#[test]
fn どの定義も閾値を下回り台帳にも無ければ種別が混ざっていても違反にしない() {
    let 台帳 = 台帳::全区画から組む();
    let 計測値 = 定義が2つある計測("未登録の型", 宣言の分量::列挙の枝数(2), 宣言の分量::構造体のフィールド数(0));
    assert!(計測1件を照合する(&台帳, &計測値).is_empty());
}

/// 台帳に登録がある所在は、どの定義が小さくても照合の相手が居る。種別も件数も決まらないまま突き合わせると、
/// 台帳の行が何の数の上限なのかを誰も確かめられない。
#[test]
fn 台帳に登録がある所在は定義が複数あれば小さくても違反にする() {
    let 台帳 = 台帳::全区画から組む();
    let 計測値 = 定義が2つある計測("アプリ", 宣言の分量::構造体のフィールド数(1), 宣言の分量::構造体のフィールド数(2));
    let 違反一覧 = 計測1件を照合する(&台帳, &計測値);
    assert_eq!(違反一覧.len(), 1);
    assert!(違反一覧[0].説明.contains("1つに決められない"), "説明: {}", 違反一覧[0].説明);
}
