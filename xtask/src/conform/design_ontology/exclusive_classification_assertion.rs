//! `クレート構文検査` の説明関数のうち、同じ軸の排他の分類を同じ型が同時に名乗っていないことを検査するもの。
//! 排他の組は `オントロジートレイト::排他の分類の組一覧` が持つ(`M不変エンティティ` と `M可変エンティティ`、`MParameter` と `MOptions`)。
//! 型の同一性(推定したモジュールパス + 型名)で両方の実装を集めて突き合わせ、両方にある型を、後の方の実装の行で違反にする(PR #169 の第1回レビューの高優先度3)。

use std::collections::HashMap;

use super::module_path::モジュールパス;
use super::syntax_checker::{クレート構文検査, トレイト実装型};
use super::syntax_patterns::オントロジートレイト;

impl クレート構文検査 {
    /// 同じ型が排他の分類の組の両方を名乗っていないこと。不変と可変は意味として同時に成り立たず、必須の束と任意の束は引数オブジェクトの軸の排他の分類である。
    pub fn 排他の分類を同時に名乗っていないこと(mut self) -> Self {
        for (甲, 乙) in オントロジートレイト::排他の分類の組一覧() {
            let 甲の一覧: HashMap<(モジュールパス, String), トレイト実装型> = self.トレイト実装型一覧(甲).into_iter().map(|型| (self.型の同一性(&型), 型)).collect();
            for 乙の型 in self.トレイト実装型一覧(乙) {
                if 甲の一覧.contains_key(&self.型の同一性(&乙の型)) {
                    self.違反にする(乙, &乙の型, 排他の違反の説明(甲));
                }
            }
        }
        self
    }
}

fn 排他の違反の説明(甲: オントロジートレイト) -> String {
    format!("は `{}` も名乗っている。同じ軸の排他の分類であり同時には成り立たないため、どちらか一方だけを名乗る({})", 甲.名前(), 排他の理由(甲))
}

fn 排他の理由(甲: オントロジートレイト) -> &'static str {
    match 甲 {
        オントロジートレイト::M不変エンティティ => "自己変更を禁じる不変エンティティと、同一性を保ったまま内部の状態を更新する可変エンティティは、意味として同時に成り立たない",
        オントロジートレイト::MParameter => "必須入力の束と任意の設定の束は、関数境界の役割の軸の排他の分類である",
        _ => "同じ軸の排他の分類である",
    }
}
