//! `クレート構文検査` の説明関数のうち、検査器が `use`・`type`・`impl` の行を読み切れたことを確かめるもの。触るのは `ソース一覧` と `違反一覧` だけである。
//! 自己変更の禁止の検査は、この3つの読み口だけで名前の辺と実装を集める。読み口が誤読した綴りを黙って飛ばすと、その `use` が持ち込む名前と、その `type` が作る辺と、その `impl` の本体の関数が、違反にも件数にもならずに検査から落ちる。
//! そのため3つの読み口は「その宣言でない」「読めた」「読み切れない」の3つだけを返し(`declaration_reading_outcome.rs`)、この説明関数が読み切れない綴りを1箇所で違反にする。
//! 根拠はグローバルCLAUDE.md「検査器は解析できなかった入力を黙って対象から外してはならない」である。走査範囲に現状0件であり、この規約は0件を保つためのものである。

use std::path::PathBuf;

use super::declaration_reading_outcome::{読めない宣言, 読めない宣言の在り処};
use super::impl_header::implの見出しを読む;
use super::impl_keyword_position::{行の頭のimplの位置, 項目の見出しを始めるimplの位置一覧};
use super::syntax_checker::クレート構文検査;
use super::type_alias_scan::型の別名の宣言を読む;
use super::use_resolution::書き出しの行付きの取り込みの項目一覧;

impl クレート構文検査 {
    /// `use`・`type`・`impl` の行のうち、検査器が読み切れないものが1つも無いこと。
    pub fn 読み切れない宣言が無いこと(mut self) -> Self {
        let 該当一覧: Vec<(PathBuf, 読めない宣言の在り処)> = self
            .ソース一覧
            .iter()
            .flat_map(|(パス, 行一覧)| ファイルの読み切れない宣言一覧(行一覧).into_iter().map(move |在り処| (パス.clone(), 在り処)))
            .collect();
        for (パス, 在り処) in 該当一覧 {
            self.違反一覧.push(在り処.違反にする(&パス));
        }
        self
    }
}

// 1つのファイルの、3つの読み口が読み切れなかった宣言の一覧。並びは行の順である。
fn ファイルの読み切れない宣言一覧(行一覧: &[String]) -> Vec<読めない宣言の在り処> {
    let mut 一覧 = 書き出しの行付きの取り込みの項目一覧(行一覧).読めない一覧;
    for (添字, 行) in 行一覧.iter().enumerate() {
        一覧.extend(型の別名の宣言を読む(行).読めなかった宣言().map(|宣言| 読めない宣言の在り処 { 行番号: 添字 + 1, 宣言 }));
        一覧.extend(読み切れないimplの見出し一覧(行一覧, 添字, 行));
    }
    一覧.sort_by_key(|在り処| 在り処.行番号);
    一覧
}

// 1つの行の中の、検査器が見出しとして読めない `impl`。行の途中から書き始めた見出しと、本体を開く `{` に届かない見出しの2つである。
fn 読み切れないimplの見出し一覧(行一覧: &[String], 添字: usize, 行: &str) -> Vec<読めない宣言の在り処> {
    let 頭の位置 = 行の頭のimplの位置(行);
    let 途中から始めた件数 = 項目の見出しを始めるimplの位置一覧(行).into_iter().filter(|位置| Some(*位置) != 頭の位置).count();
    let 本体に届かないか = 頭の位置.is_some() && implの見出しを読む(行一覧, 添字).is_none();
    let 理由一覧 = [
        (途中から始めた件数 > 0).then_some("`impl` の見出しを行の途中から書き始めている。検査器が見出しとして読むのは行の頭の `impl` だけである"),
        本体に届かないか.then_some("`impl` の見出しの本体を開く `{` が、そのファイルの中に見つからない"),
    ];
    理由一覧
        .into_iter()
        .flatten()
        .map(|理由| 読めない宣言の在り処 {
            行番号: 添字 + 1,
            宣言: 読めない宣言 { 綴り: 行.trim().to_string(), 理由 },
        })
        .collect()
}
