//! `クレート構文検査` の説明関数のうち、検査器が `use`・`type`・`impl` の宣言を読み切れたことを確かめるもの。触るのは `ソース一覧` と `違反一覧` だけである。
//! 自己変更の禁止の検査は、この3つの読み口だけで名前の辺と実装を集める。読み口が読み切れなかった綴りを黙って飛ばすと、その `use` が持ち込む名前と、その `type` が作る辺と、その `impl` の本体の関数が、違反にも件数にもならずに検査から落ちる。
//! 3つの読み口が読むのは行の頭の宣言だけである。そのため、項目の予約語を行の頭でない位置に書いた綴り(`item_keyword_position.rs`)と、行の頭から読み始めて読み切れなかった綴りの2つを、この説明関数が1箇所で違反にする。
//! 根拠はグローバルCLAUDE.md「検査器は解析できなかった入力を黙って対象から外してはならない」である。走査範囲に現状0件であり、この規約は0件を保つためのものである。

use std::path::PathBuf;

use super::declaration_reading_outcome::{読めない宣言, 読めない宣言の在り処};
use super::impl_header::implの見出しを読む;
use super::item_keyword_position::項目の予約語の走査;
use super::line_matching::implの予約語より後ろ;
use super::syntax_checker::クレート構文検査;
use super::type_alias_scan::型の別名の宣言を読む;
use super::use_resolution::書き出しの行付きの取り込みの項目一覧;

impl クレート構文検査 {
    /// `use`・`type`・`impl` の宣言のうち、検査器が読み切れないものが1つも無いこと。
    pub fn 読み切れない宣言が無いこと(mut self) -> Self {
        let 該当一覧: Vec<(PathBuf, 読めない宣言の在り処)> = self
            .ソース一覧
            .iter()
            .flat_map(|(パス, 行一覧)| ファイルの読み切れない宣言一覧(行一覧).into_iter().map(move |在り処| (パス.clone(), 在り処)))
            .collect();
        for (パス, 在り処) in 該当一覧 {
            self.違反一覧.push(在り処.違反にする(&パス));
        }
        self
    }
}

// 1つのファイルの、検査器が読み切れなかった宣言の一覧。並びは行の順である。
fn ファイルの読み切れない宣言一覧(行一覧: &[String]) -> Vec<読めない宣言の在り処> {
    let mut 一覧 = 書き出しの行付きの取り込みの項目一覧(行一覧).読めない一覧;
    let mut 予約語の走査 = 項目の予約語の走査::default();
    for (添字, 行) in 行一覧.iter().enumerate() {
        let 在り処にする = |理由: &'static str| 読めない宣言の在り処 {
            行番号: 添字 + 1,
            宣言: 読めない宣言 { 綴り: 行.trim().to_string(), 理由 },
        };
        一覧.extend(予約語の走査.行の頭でない項目の予約語一覧(行).into_iter().map(|予約語| 在り処にする(予約語.行の頭でない理由())));
        一覧.extend(型の別名の宣言を読む(行一覧, 添字).読めなかった宣言().map(|宣言| 読めない宣言の在り処 { 行番号: 添字 + 1, 宣言 }));
        if implの予約語より後ろ(行).is_some() && implの見出しを読む(行一覧, 添字).is_none() {
            一覧.push(在り処にする("`impl` の見出しの本体を開く `{` が、そのファイルの中に見つからない"));
        }
    }
    一覧.sort_by_key(|在り処| 在り処.行番号);
    一覧
}
