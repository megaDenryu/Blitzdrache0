//! コードだけの行を先頭の行から順に字句へ分け、項目の予約語(`impl`・`type`・`use`)の現れごとに、直前の字句とトークン木の中かを答える走査。受け取るのは1行、返すのはその行の予約語の現れの一覧である。
//! 直前の字句は、コメントを除いて前の行をまたいで求める。コメントと文字列と文字は `source_lexing` のコードだけの行が先に落としているため、その中の括弧と語は数えない。
//! トークン木の中かは `token_tree_nesting.rs` が答える。生の識別子(`r#type`)と寿命(`'a`)は1つの字句として読み、予約語として数えない。

use super::item_keyword_position::項目の予約語;
use super::token_tree_nesting::トークン木の入れ子;

/// 項目の予約語の直前にある字句の区分。項目を始めうるかを予約語ごとに決めるために、その判定に要る字句だけを区別する。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum 直前の字句 {
    #[default]
    項目の区切り,
    可視性を閉じる丸括弧,
    予約語のunsafe,
    予約語のdefault,
    予約語のpub,
    その他,
}

/// 行の中の項目の予約語の現れ1件。位置はその行の中のバイト位置である。
pub struct 予約語の現れ {
    pub 位置: usize,
    pub 予約語: 項目の予約語,
    pub 直前: 直前の字句,
    pub トークン木の中か: bool,
}

/// 項目の予約語の現れを読む字句の走査。直前の字句と括弧の入れ子を行をまたいで持つため、1つのファイルを先頭の行から順に読む。
/// 直前の字句の既定を項目の区切りにするのは、ファイルの先頭が項目を始める位置であるためである。
#[derive(Default)]
pub struct 予約語の字句の走査 {
    直前: 直前の字句,
    入れ子: トークン木の入れ子,
}

impl 予約語の字句の走査 {
    /// 1行を読み、その行の中の項目の予約語の現れの一覧を返す。並びは行の中の位置の順である。
    pub fn 行を読む(&mut self, 行: &str) -> Vec<予約語の現れ> {
        let mut 現れ一覧 = Vec::new();
        let mut 位置 = 0;
        while let Some(文字) = 行.get(位置..).and_then(|残り| 残り.chars().next()) {
            let 残り = &行[位置..];
            if 文字 == '\'' {
                self.記号を読んだ(直前の字句::その他);
                位置 += 1 + 先頭の語(&残り[1..]).len();
            } else if 生の識別子の前置きか(残り) {
                let 生の識別子 = &残り[..2 + 先頭の語(&残り[2..]).len()];
                self.入れ子.語を読む(生の識別子);
                self.直前 = 直前の字句::その他;
                位置 += 生の識別子.len();
            } else if let Some(語) = Some(先頭の語(残り)).filter(|語| !語.is_empty()) {
                self.語を読む(語, 位置, &mut 現れ一覧);
                位置 += 語.len();
            } else {
                self.記号を読む(文字);
                位置 += 文字.len_utf8();
            }
        }
        現れ一覧
    }

    fn 語を読む(&mut self, 語: &str, 位置: usize, 現れ一覧: &mut Vec<予約語の現れ>) {
        if let Some(予約語) = 項目の予約語::表記から読む(語) {
            現れ一覧.push(予約語の現れ {
                位置,
                予約語,
                直前: self.直前,
                トークン木の中か: self.入れ子.中か(),
            });
        }
        self.入れ子.語を読む(語);
        self.直前 = match 語 {
            "unsafe" => 直前の字句::予約語のunsafe,
            "default" => 直前の字句::予約語のdefault,
            "pub" => 直前の字句::予約語のpub,
            _ => 直前の字句::その他,
        };
    }

    fn 記号を読む(&mut self, 文字: char) {
        match 文字 {
            _ if 文字.is_whitespace() => {}
            '!' => {
                self.入れ子.感嘆符を読む();
                self.直前 = 直前の字句::その他;
            }
            '(' | '[' | '{' => {
                self.入れ子.開き括弧を読む(文字 == '(' && self.直前 == 直前の字句::予約語のpub);
                self.直前 = if 文字 == '{' { 直前の字句::項目の区切り } else { 直前の字句::その他 };
            }
            ')' | ']' | '}' => {
                let 可視性を閉じたか = self.入れ子.閉じ括弧を読む();
                self.直前 = match 文字 {
                    ')' if 可視性を閉じたか => 直前の字句::可視性を閉じる丸括弧,
                    ')' => 直前の字句::その他,
                    _ => 直前の字句::項目の区切り,
                };
            }
            ';' => self.記号を読んだ(直前の字句::項目の区切り),
            _ => self.記号を読んだ(直前の字句::その他),
        }
    }

    fn 記号を読んだ(&mut self, 直前: 直前の字句) {
        self.直前 = 直前;
        self.入れ子.その他の記号を読む();
    }
}

// 先頭から識別子の文字(英数字・下線・非ASCIIの文字)が続く限り。
fn 先頭の語(残り: &str) -> &str {
    let 長さ = 残り.char_indices().find(|(_, 文字)| !(文字.is_alphanumeric() || *文字 == '_')).map_or(残り.len(), |(位置, _)| 位置);
    &残り[..長さ]
}

// 生の識別子(`r#type`)の前置きの `r#` で始まるか。
fn 生の識別子の前置きか(残り: &str) -> bool {
    残り.strip_prefix("r#").and_then(|後ろ| 後ろ.chars().next()).is_some_and(|文字| 文字.is_alphanumeric() || 文字 == '_')
}
