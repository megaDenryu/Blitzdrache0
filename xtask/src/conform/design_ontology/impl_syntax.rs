/// 実装の種類。トレイトの実装はトレイトを書いた位置の表記(`変更`・`crate::a::変更<u8>`)を持つ。
pub enum 実装の種類 {
    固有の実装,
    トレイトの実装 { トレイトの表記: String },
}

pub struct 実装の見出しの構文 {
    pub 種類: 実装の種類,
    pub 対象: 実装の対象の型,
    pub 境界: 実装の境界,
    型引数の名前一覧: Vec<String>, // 寿命を除いた型引数と定数の引数の名前(`impl<'a, T: Clone, const N: usize>` なら `T` と `N`)
}

impl 実装の見出しの構文 {
    pub fn 読む(表記: &str) -> Option<Self> {
        let (型引数, 残り) = 先頭の型引数を分ける(implの予約語より後ろ(表記)?.trim_start());
        let (宣言, 境界の句) = 宣言と境界の句に分ける(残り);
        let (種類, 対象の表記) = match 最上位のforの位置(宣言) {
            Some(位置) => (
                実装の種類::トレイトの実装 {
                    トレイトの表記: 宣言[..位置].trim().to_string(),
                },
                &宣言[位置 + "for".len()..],
            ),
            None => (実装の種類::固有の実装, 宣言),
        };
        Some(Self {
            種類,
            対象: 実装の対象の型::表記から読む(対象の表記),
            境界: 実装の境界::表記から読む(型引数, 境界の句),
            型引数の名前一覧: 型の引数の名前一覧(型引数),
        })
    }

    /// トレイトの実装なら、トレイトを書いた位置の表記。固有の実装なら無い。
    pub fn トレイトの表記(&self) -> Option<&str> {
        match &self.種類 {
            実装の種類::固有の実装 => None,
            実装の種類::トレイトの実装 { トレイトの表記 } => Some(トレイトの表記),
        }
    }

    /// 対象の型を名前だけ(パスで修飾しない型名と型引数)で書いた固有の実装で、その型名が `型名` か。`impl 型名 {`・`impl<T> 型名<T> {` が当たり、`impl crate::a::型名 {` は当たらない。
    pub fn 名前だけで書いた型の固有の実装か(&self, 型名: &str) -> bool {
        matches!(self.種類, 実装の種類::固有の実装) && 先頭の識別子(self.対象.表記()) == 型名
    }

    /// 値で受ける `self` の関数も含め、どの関数も対象の型の値を書き換えうる実装か。対象の表記のどの深さにでも可変参照か可変の借用を与えるトレイトが現れるとき(`Option<&mut 規則>`・`Box<dyn DerefMut<Target = 規則>>`)と、見出しの境界の可変の借用を与えるトレイトの型引数が `Self` を指すとき(`impl<U: DerefMut<Target = Self>> 変更<U> for 規則`)と、見出しの境界に `Self` への可変参照が字面で現れるとき(`impl<'a, I: Iterator<Item = &'a mut Self>> 変更<I> for 規則`)である。
    /// 境界の `Self` は対象の型そのものを指すため、`fn 変える(mut 相手: U)` は受け手と引数の字面に可変参照を持たずに対象の型の値を書き換える。
    pub fn どの関数も自己変更を与える実装か(&self) -> bool {
        self.対象.可変参照か() || 可変の借用を与えるトレイトが現れるか(self.対象.表記()) || self.境界.可変の借用で名前を指すか("Self") || self.境界.自分の型への可変参照を字面に含むか("Self")
    }

    /// 寿命を除いた型引数と定数の引数の名前の一覧。
    pub fn 型引数の名前一覧(&self) -> &[String] {
        &self.型引数の名前一覧
    }

    /// 対象の型が実装自身の型引数である全称の実装(`impl<T: 境界> トレイト for T`・`for &mut T`・`for &mut &mut T`・`for Pin<&mut T>`)か。検査器は境界を評価できず、対象の型を具体の型へ結び付けられない。
    /// 参照と `Pin` を繰り返し外した後の名前が型引数なら全称の実装である。外しきれない形(`Pin<Box<T>>` のように `Pin` のまま残った表記)に型引数が識別子として現れるときも、見落とさない側へ倒して全称の実装とみなす。参照は必ず外しきれる。
    pub fn 全称の実装か(&self) -> bool {
        let 外した = self.対象.参照とpinを外しきった表記();
        let 外しきれないか = パスの最後の名前(外した) == "Pin";
        self.型引数の名前一覧.iter().any(|名前| 名前 == パスの最後の名前(外した) || (外しきれないか && 識別子として現れるか(外した, 名前)))
    }

    /// 参照と `Pin` を繰り返し外した後の対象の型の名前。対象の型を決められない実装の自己変更を問う相手の名前である。
    pub fn 外しきった対象の名前(&self) -> &str {
        パスの最後の名前(self.対象.参照とpinを外しきった表記())
    }
}

// どの括弧の中でもない位置に識別子の境界で現れる `for` の開始位置。トレイトの型引数(`変更<fn(u8) -> u8>`)の中を探さない。
// 空白の一致(` for `)で探さないのは、`for(規則)`・`for&mut 規則` を固有の実装と読み違えるためである。高階の寿命の束縛(`dyn for<'a> Fn(&'a u8)`)の `for` は除く。
fn 最上位のforの位置(宣言: &str) -> Option<usize> {
    let 現れ一覧 = 識別子として現れる位置一覧(宣言, "for");
    let mut 括弧 = 見出しの括弧の深さ::default();
    for (位置, 文字) in 宣言.char_indices() {
        if 括弧.最上位か() && 現れ一覧.contains(&位置) && !高階の寿命の束縛か(&宣言[位置 + "for".len()..]) {
            return Some(位置);
        }
        括弧.一文字読む(文字);
    }
    None
}

// `for` の後ろが高階の寿命の束縛の山括弧(`<'a>`・`<>`)か。実装の対象の型は山括弧で始まれない(関連型の射影は正規形が禁じる)ため、`<` の後ろが寿命か閉じ括弧なら束縛である。
fn 高階の寿命の束縛か(後ろ: &str) -> bool {
    後ろ.trim_start().strip_prefix('<').is_some_and(|山括弧の中| 山括弧の中.trim_start().starts_with(['\'', '>']))
}
