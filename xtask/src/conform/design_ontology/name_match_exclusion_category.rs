//! 名前が当たった別の型の実装の台帳が行を除いてよい区分と、区分ごとに `除外する理由` が示さなければならない条文。
//! 名前の過大近似がマーカーの型でない実装を拾う経路は4つあり、そのどれもを「同じ名前の別の型である」では言えない。
//! 第一に、区切られたドメインが違うために同じ表記を持つ別の型の実装である。第二に、マーカーの型を包む型(`Box`・`Vec`・`Option`・スライス・組)の実装である。包む型は別の型ではないが、包んだ値を書き換えない実装なら除いてよい。
//! 第三に、関連型の宣言(`type Output = 型;`)の辺で名前の閉包へ入った名前の実装である。この名前はマーカーの型を指さない。
//! 第四に、型引数の並びの境界か `where` 句か関数の署名の境界でマーカーの型を指す実装(`impl<T: Into<地点>> 記録器<T>`・`fn 積む<T: Into<地点>>(&mut self, 値: T)`)である。境界で当たった実装は値で受ける `self` の関数も数えるため、境界が書き換えを与えない実装も当たる。
//! 区分を裸の文字列で持つのは、台帳が `const` の配列であり、検証つきの生成の口を通せないためである。台帳の行が名乗る区分がこの一覧にあることは、台帳の突き合わせが違反として確かめる。
//! 参照: `_doc/設計/設計オントロジー.md` 2.5.3 の自己変更の禁止の読む範囲。

/// 除いてよい区分の呼び名と、その区分で除くときに `除外する理由` が示さなければならない条文。
pub const 区分ごとの条文: [(&str, &str); 4] = [
    ("同じ名前の別の型", "その実装の対象が、マーカーを名乗る型と同じ表記を持つ別の型であることを示す"),
    ("型を包む実装", "その実装の対象がマーカーの型を包む型であり、その可変の受け手が包んだ値を書き換えないことを示す"),
    ("関連型の辺で入った名前", "その名前が関連型の宣言の辺で名前の閉包へ入ったものであり、マーカーの型を指さないことを示す"),
    (
        "境界で指した名前",
        "その名前が型引数の並びの境界か `where` 句か関数の署名の境界にだけ現れ、その境界がマーカーの型の値への可変の参照も可変の借用も与えない(`Into`・`From`・`Clone` のように値を作るか読むだけである)ことを示す",
    ),
];

/// その区分が、台帳の行が名乗ってよい区分か。
pub fn 除いてよい区分か(区分: &str) -> bool {
    区分ごとの条文.iter().any(|(呼び名, _)| *呼び名 == 区分)
}

/// 名乗ってよい区分とその条文を1つの文へ並べたもの。区分を名乗り損ねた行の違反の説明が、そのまま読み手へ返す。
pub fn 区分と条文の並び() -> String {
    区分ごとの条文.iter().map(|(呼び名, 条文)| format!("`{呼び名}`(理由に{条文})")).collect::<Vec<_>>().join("、")
}
