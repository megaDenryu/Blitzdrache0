//! 名前を探した結果の値。名前の在り処の探索(`module_index/name_location_search.rs`)が返し、実装の対象の型を結び付ける工程(`implementation_binding.rs`)と、トレイトの宣言を引く工程(`implemented_trait/declaring_module.rs`)が読む。
//! どちらの値も、候補ごとの結果を1つに決めずに合わせて持つ。cfg で切り替わる取り込みと宣言のように、同じ名前が複数の候補から見えるとき、検査器は cfg を評価できず、
//! ソースの並びで最初に現れた候補を Rust の名前の解き方の結果として扱うと、別の候補が指す可変のトレイトや `M不変データ` の型を黙って見落とすためである。

use super::super::module_path::モジュールパス;

/// 名前を探した結果。名前を宣言しているモジュールと、たどり切れなかった取り込みが指しうるモジュールと、`use … as` の別名を通しているかを持つ。3つとも空なら見つからない。
#[derive(Default)]
pub struct 名前の在り処 {
    pub 宣言したモジュール一覧: Vec<モジュールパス>,
    pub たどり切れなかったモジュール一覧: Vec<モジュールパス>, // 1段たどった先でさらに名前か glob を取り込む(探す深さの上限を超えた)取り込みが指しうるモジュール
    pub 別名を通しているか: bool,
}

impl 名前の在り処 {
    /// 複数の探し方の結果を、どれも捨てずに1つにする。
    pub fn 合わせる(一覧: impl IntoIterator<Item = Self>) -> Self {
        let mut 合わせた = Self::default();
        for 在り処 in 一覧 {
            合わせた.宣言したモジュール一覧.extend(在り処.宣言したモジュール一覧);
            合わせた.たどり切れなかったモジュール一覧.extend(在り処.たどり切れなかったモジュール一覧);
            合わせた.別名を通しているか |= 在り処.別名を通しているか;
        }
        合わせた
    }

    /// 宣言も、たどり切れなかった取り込みも、別名も無いか。
    pub fn 見つからないか(&self) -> bool {
        self.宣言したモジュール一覧.is_empty() && self.たどり切れなかったモジュール一覧.is_empty() && !self.別名を通しているか
    }
}

/// 修飾の無い名前を、実装の位置のモジュールの宣言と `use` から探した結果。明示の取り込みと glob の取り込みを、取り込みの項目ごとの在り処として分けて持つ。
/// glob の在り処は、そのモジュールに同じ名前の宣言か明示の取り込みがあれば、それらが glob を隠すため持たない。ただし宣言か明示の取り込みが条件付き(cfg)なら、glob の側も候補として持つ。
pub struct 修飾の無い名前の在り処 {
    pub 自分が宣言しているか: bool,
    pub 別名を通しているか: bool,
    pub 明示の取り込みごとの在り処: Vec<名前の在り処>,
    pub globごとの在り処: Vec<名前の在り処>,
}
