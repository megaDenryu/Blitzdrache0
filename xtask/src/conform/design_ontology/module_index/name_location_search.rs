//! 名前の宣言がどのモジュールにあるかを、候補のモジュールとその `use` の1段から探す工程。受け取るのは候補のモジュールの一覧か実装の位置のモジュール、返すのは名前の在り処(`module_index/name_location.rs`)である。
//! モジュールの `use` は、索引がそのモジュールの直下に書いたものだけを返す(波括弧付きのモジュールの中の `use` は外側のモジュールの取り込みに数えず、局所の `use` はどのモジュールの取り込みにも数えない)。
//! 実装の対象の型を定義へ結び付ける工程(`implementation_binding.rs`)と、実装したトレイトの宣言を引く工程(`implemented_trait/declaring_module.rs`)が、同じ規則で名前を探すために共有する。
//! 1つのモジュールでの名前の束縛は、その名前の宣言と明示の取り込みと glob の取り込みである。宣言と明示の取り込みは全部を候補として持つ。同じモジュールで同じ名前を2つ以上束縛できるのは cfg で切り替わるときだけであり、検査器は cfg を評価しないためである。
//! glob の取り込みは、そのモジュールに同じ名前の宣言か明示の取り込みがあれば、それらが glob を隠すため候補にしない。ただしその宣言か明示の取り込みが条件付き(cfg)なら、消える場合があるため glob も候補にする。
//! 走査範囲の外のクレートを指す明示の取り込み(`use thiserror::Error;`)は glob を隠すものとして数えない。その名前が derive のマクロのように型と別の名前空間の名前でありうるのに、検査器は走査範囲の外の宣言を読めず、名前空間を知らないためである。
//! 候補のモジュールの束縛の宣言をそのモジュールに、取り込みを1段たどった先の宣言をその先のモジュールに数える。1段たどった先が走査範囲のモジュールで、宣言が無くさらに名前か glob を取り込んでいれば、探す深さの上限を超えたとして、その取り込みが指すモジュールを添える。
//! 宣言しているかの判定は呼び出し側が持つ(型なら `struct`・`enum` の定義、トレイトならトレイトの宣言の索引)。

use super::super::module_path::モジュールパス;
use super::super::use_resolution::取り込みの項目;
use super::name_location::{修飾の無い名前の在り処, 名前の在り処};
use super::モジュールの索引;

/// 名前を探す相手。モジュールの索引と、探す名前と、あるモジュールがその名前を宣言しているかの判定の組である。
pub struct 名前の在り処の探索<'a, F> {
    pub 索引: &'a モジュールの索引,
    pub 名前: &'a str,
    pub 宣言しているか: F,
}

// 1つのモジュールでの、探す名前の取り込み。宣言は含まない。
struct 名前の取り込み<'b> {
    明示の取り込み一覧: Vec<&'b 取り込みの項目>, // 名前を名乗る取り込み(別名を含む)
    glob一覧: Vec<&'b 取り込みの項目>,           // 候補にする glob の取り込み
    別名を通しているか: bool,
}

impl<F: Fn(&モジュールパス) -> bool> 名前の在り処の探索<'_, F> {
    /// 候補のモジュールの束縛と、その取り込みを1段たどった先から、名前を宣言しているモジュールを探す。
    pub fn 候補から探す(&self, 候補一覧: &[モジュールパス]) -> 名前の在り処 {
        let mut 在り処 = 名前の在り処::default();
        let mut 一段先 = Vec::new();
        for 候補 in 候補一覧 {
            if (self.宣言しているか)(候補) {
                在り処.宣言したモジュール一覧.push(候補.clone());
            }
            let 取り込み = self.名前の取り込み(候補);
            在り処.別名を通しているか |= 取り込み.別名を通しているか;
            let 名乗る明示の取り込み = 取り込み.明示の取り込み一覧.into_iter().filter(|項目| 項目.別名.is_none());
            一段先.extend(名乗る明示の取り込み.chain(取り込み.glob一覧).flat_map(|項目| 候補.書かれたパスが指しうるモジュール一覧(項目.親のパス())));
        }
        for 先 in 一段先 {
            if (self.宣言しているか)(&先) {
                在り処.宣言したモジュール一覧.push(先);
            } else if self.索引.モジュールが在るか(&先) {
                let 取り込み = self.名前の取り込み(&先);
                let 続き = 取り込み.明示の取り込み一覧.into_iter().chain(取り込み.glob一覧);
                在り処.たどり切れなかったモジュール一覧.extend(続き.flat_map(|項目| 先.書かれたパスが指しうるモジュール一覧(項目.親のパス())));
            }
        }
        在り処
    }

    /// 修飾の無い名前を、実装の位置のモジュールの宣言と、明示の取り込みと glob の取り込みの項目ごとに探す。
    pub fn 修飾の無い名前を取り込みから探す(&self, 自分: &モジュールパス) -> 修飾の無い名前の在り処 {
        let 取り込み = self.名前の取り込み(自分);
        let 項目ごとに探す = |一覧: Vec<&取り込みの項目>| -> Vec<名前の在り処> {
            一覧
                .into_iter()
                .filter(|項目| 項目.別名.is_none())
                .map(|項目| self.候補から探す(&自分.書かれたパスが指しうるモジュール一覧(項目.親のパス())))
                .collect()
        };
        修飾の無い名前の在り処 {
            自分が宣言しているか: (self.宣言しているか)(自分),
            別名を通しているか: 取り込み.別名を通しているか,
            明示の取り込みごとの在り処: 項目ごとに探す(取り込み.明示の取り込み一覧),
            globごとの在り処: 項目ごとに探す(取り込み.glob一覧),
        }
    }

    // そのモジュールの直下の、探す名前を名乗る取り込みと、候補にする glob の取り込み。
    fn 名前の取り込み<'b>(&'b self, モジュール: &モジュールパス) -> 名前の取り込み<'b> {
        let 項目一覧 = self.索引.取り込みの項目一覧(モジュール);
        let 明示の取り込み一覧: Vec<&取り込みの項目> = 項目一覧.iter().filter(|項目| !項目.全部を取り込むか() && 項目.名乗る名前() == self.名前).collect();
        let 隠す明示の取り込みがあるか = 明示の取り込み一覧.iter().any(|項目| self.索引.取り込みが走査範囲のクレートを指すか(モジュール, 項目));
        let 隠されているか = (隠す明示の取り込みがあるか || (self.宣言しているか)(モジュール)) && !self.索引.条件付きで束縛しているか(モジュール, self.名前);
        名前の取り込み {
            別名を通しているか: 明示の取り込み一覧.iter().any(|項目| 項目.別名.is_some()),
            glob一覧: if 隠されているか {
                Vec::new()
            } else {
                項目一覧.iter().filter(|項目| 項目.全部を取り込むか()).collect()
            },
            明示の取り込み一覧,
        }
    }
}
