//! 名前の宣言がどのモジュールにあるかを、候補のモジュールとその `use` の1段から探す工程。受け取るのは候補のモジュールの一覧か実装の位置のモジュール、返すのは名前の在り処である。
//! モジュールの `use` は、索引がそのモジュールに書いたものだけを返す(波括弧付きのモジュールの中の `use` は外側のモジュールの取り込みに数えない)。
//! 実装の対象の型を定義へ結び付ける工程(`implementation_binding.rs`)と、実装したトレイトの宣言を引く工程(`implemented_trait/declaring_module.rs`)が、同じ規則で名前を探すために共有する。
//! 候補のどれかが名前を宣言していればそのモジュールである。無ければ候補のモジュールの `use`(再公開の `pub use` を含む)を、明示の取り込みを先に、glob を後に1段たどる。
//! 1段たどった先にも宣言が無く、その先が走査範囲のモジュールでさらに名前か glob を取り込んでいれば、探す深さの上限を超えたと答え、たどり切れなかった取り込みが指すモジュールを添える。
//! 宣言しているかの判定は呼び出し側が持つ(型なら `struct`・`enum` の定義、トレイトならトレイトの宣言の索引)。

use super::super::module_path::モジュールパス;
use super::super::use_resolution::取り込みの項目;
use super::モジュールの索引;

/// 名前を探した結果。
pub enum 名前の在り処 {
    見つかった(Vec<モジュールパス>),   // 名前を宣言しているモジュールの一覧
    別名を通している,                  // 候補のモジュールの `use … as 名前` が名前を名乗らせている
    深さを超えた(Vec<モジュールパス>), // たどり切れなかった取り込みが指しうるモジュールの一覧
    見つからない,
}

impl 名前の在り処 {
    /// 複数の探し方の結果を1つにする。別名を通すものが1つでもあれば別名、見つかったものがあればその全部、無ければたどり切れなかったものの全部である。
    pub fn 合わせる(一覧: impl IntoIterator<Item = Self>) -> Self {
        let (mut 見つかった一覧, mut 続きの一覧) = (Vec::new(), Vec::new());
        for 在り処 in 一覧 {
            match 在り処 {
                Self::別名を通している => return Self::別名を通している,
                Self::見つかった(一覧) => 見つかった一覧.extend(一覧),
                Self::深さを超えた(一覧) => 続きの一覧.extend(一覧),
                Self::見つからない => {}
            }
        }
        match (見つかった一覧.is_empty(), 続きの一覧.is_empty()) {
            (false, _) => Self::見つかった(見つかった一覧),
            (true, false) => Self::深さを超えた(続きの一覧),
            (true, true) => Self::見つからない,
        }
    }
}

/// 修飾の無い名前を実装のモジュールの `use` から探した結果。明示の取り込みから探したか glob から探したかを区別する(明示の取り込みは glob より先に名前を決めるため)。
pub enum 修飾の無い名前の在り処 {
    別名を通している,
    明示の取り込みから(名前の在り処),
    名前を全部取り込む取り込みから(名前の在り処),
    取り込んでいない,
}

/// 名前を探す相手。モジュールの索引と、探す名前と、あるモジュールがその名前を宣言しているかの判定の組である。
pub struct 名前の在り処の探索<'a, F> {
    pub 索引: &'a モジュールの索引<'a>,
    pub 名前: &'a str,
    pub 宣言しているか: F,
}

impl<F: Fn(&モジュールパス) -> bool> 名前の在り処の探索<'_, F> {
    /// 候補のモジュールと、その `use` を明示の取り込み・glob の順に1段たどった先から、名前を宣言しているモジュールを探す。
    pub fn 候補から探す(&self, 候補一覧: &[モジュールパス]) -> 名前の在り処 {
        if let Some(在り処) = self.宣言したモジュールの在り処(候補一覧) {
            return 在り処;
        }
        let 組一覧 = self.取り込みの組一覧(候補一覧);
        if 組一覧.iter().any(|(_, 項目)| 項目.別名.as_deref() == Some(self.名前)) {
            return 名前の在り処::別名を通している;
        }
        let 明示の先 = 指しうるモジュール一覧(&組一覧, |項目| 項目.別名.is_none() && 項目.元の名前() == self.名前);
        let globの先 = 指しうるモジュール一覧(&組一覧, 取り込みの項目::全部を取り込むか);
        if let Some(在り処) = self.宣言したモジュールの在り処(&明示の先).or_else(|| self.宣言したモジュールの在り処(&globの先)) {
            return 在り処;
        }
        let 走査範囲の先: Vec<モジュールパス> = 明示の先.into_iter().chain(globの先).filter(|モジュール| self.索引.モジュールが在るか(モジュール)).collect();
        let 続きの先 = 指しうるモジュール一覧(&self.取り込みの組一覧(&走査範囲の先), |項目| 項目.名乗る名前() == self.名前 || 項目.全部を取り込むか());
        if 続きの先.is_empty() {
            名前の在り処::見つからない
        } else {
            名前の在り処::深さを超えた(続きの先)
        }
    }

    /// 修飾の無い名前を、実装の位置のモジュールの `use` の別名・明示の取り込み・glob の取り込みの順に探す。glob が複数あれば全部の結果を合わせる。
    pub fn 修飾の無い名前を取り込みから探す(&self, 自分: &モジュールパス) -> 修飾の無い名前の在り処 {
        let 項目一覧 = self.索引.取り込みの項目一覧(自分);
        if 項目一覧.iter().any(|項目| 項目.別名.as_deref() == Some(self.名前)) {
            return 修飾の無い名前の在り処::別名を通している;
        }
        if let Some(項目) = 項目一覧.iter().find(|項目| 項目.別名.is_none() && 項目.元の名前() == self.名前) {
            return 修飾の無い名前の在り処::明示の取り込みから(self.候補から探す(&自分.書かれたパスが指しうるモジュール一覧(項目.親のパス())));
        }
        let globの在り処一覧: Vec<名前の在り処> = 項目一覧
            .iter()
            .filter(|項目| 項目.全部を取り込むか())
            .map(|項目| self.候補から探す(&自分.書かれたパスが指しうるモジュール一覧(項目.親のパス())))
            .collect();
        if globの在り処一覧.is_empty() {
            return 修飾の無い名前の在り処::取り込んでいない;
        }
        修飾の無い名前の在り処::名前を全部取り込む取り込みから(名前の在り処::合わせる(globの在り処一覧))
    }

    // 候補のうち名前を宣言しているモジュールの全部。1つも無ければ無い。
    fn 宣言したモジュールの在り処(&self, 候補一覧: &[モジュールパス]) -> Option<名前の在り処> {
        let 一覧: Vec<モジュールパス> = 候補一覧.iter().filter(|モジュール| (self.宣言しているか)(モジュール)).cloned().collect();
        (!一覧.is_empty()).then_some(名前の在り処::見つかった(一覧))
    }

    fn 取り込みの組一覧<'b>(&'b self, 候補一覧: &'b [モジュールパス]) -> Vec<(&'b モジュールパス, &'b 取り込みの項目)> {
        候補一覧.iter().flat_map(|モジュール| self.索引.取り込みの項目一覧(モジュール).iter().map(move |項目| (モジュール, 項目))).collect()
    }
}

// 組の一覧のうち条件に合う取り込みが、取り込みを書いたモジュールから指しうるモジュールの一覧。
fn 指しうるモジュール一覧(組一覧: &[(&モジュールパス, &取り込みの項目)], 条件: impl Fn(&取り込みの項目) -> bool) -> Vec<モジュールパス> {
    組一覧.iter().filter(|(_, 項目)| 条件(項目)).flat_map(|(モジュール, 項目)| モジュール.書かれたパスが指しうるモジュール一覧(項目.親のパス())).collect()
}
