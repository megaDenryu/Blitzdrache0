//! 項目の予約語(`impl`・`type`・`use`)が行の頭に在るかを読む走査。受け取るのはコードだけの1行、返すのはその行の中の、行の頭でない位置に書いた、項目を始めうる予約語の一覧である。
//! 検査器が宣言として読むのは行の頭の3つだけである(`impl_header.rs`・`type_alias_scan.rs`・`use_resolution.rs`)。行の途中に書いた宣言はどの読み口にも当たらず、違反にも件数にもならずに落ちる。
//! 行の頭とは、字下げと属性と可視性(`impl` では可視性の代わりに `unsafe`)を読み飛ばした位置のことであり、3つの読み口が読み始める位置と同じである。
//! 行の頭でない現れを違反にするかは、2つの規則で決める。トークン木(マクロの呼び出しの引数と `macro_rules!` の本体)の外では、直前の字句が、文法の上で項目を始めうる字句の閉じた集合に入るときだけ違反にする。
//! 集合は、`impl` では `{`・`}`・`;`・`]`・`unsafe`・`default`、`type` と `use` では `{`・`}`・`;`・`]`・`pub`・`pub(..)` を閉じる `)` である。型の位置の `impl`(`->`・`:`・`&`・`'a`・`<`・`,`・`=`・`(`・`[`・`mut` の後ろ)と
//! 精密な捕捉の `use<'a>`(`+` の後ろ)と属性の中の語(`(`・`,`・`=` の後ろ)は、この集合に入らないため数えない。項目を始めない前置きを列挙して除く形をやめたのは、列挙の漏れが検査器の読まない宣言を黙って通すためである。
//! トークン木の中では、マクロが字句をどう並べ替えて展開するかを検査器が知らないため、例外なしにすべての現れを違反にする。字句の走査は `item_keyword_lexer.rs` が持つ。
//! 整形(rustfmt)は行の途中の宣言を減らすが、整形しきれない文を元の1行のまま残すため、この検査の健全性は整形に預けず、字句の集合が保証する。走査範囲(`crates` 配下の `src`)の現状は0件である。

use super::declaration_prefix::{先頭の属性を読み飛ばす, 属性と可視性を読み飛ばす};
use super::item_keyword_lexer::{予約語の字句の走査, 直前の字句};

/// 項目を始める3つの予約語。検査器はこの3つを行の頭でだけ読む。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 項目の予約語 {
    実装,
    型の別名,
    取り込み,
}

impl 項目の予約語 {
    /// 語がこの3つの予約語のどれかなら、その予約語。
    pub fn 表記から読む(語: &str) -> Option<Self> {
        match 語 {
            "impl" => Some(Self::実装),
            "type" => Some(Self::型の別名),
            "use" => Some(Self::取り込み),
            _ => None,
        }
    }

    /// 行の頭でない位置に書いたときの、読み切れない理由。違反の説明がそのまま読み手へ返す。
    pub const fn 行の頭でない理由(self) -> &'static str {
        match self {
            Self::実装 => "`impl` を行の頭でない位置に書いている。検査器が実装として読むのは行の頭の `impl` だけであり、行の途中の実装の本体の関数を黙って検査から落とすため、行を改めて行の頭に書く",
            Self::型の別名 => "`type` を行の頭でない位置に書いている。検査器が型の別名として読むのは行の頭の `type` だけであり、行の途中の別名が作る名前の辺を黙って検査から落とすため、行を改めて行の頭に書く",
            Self::取り込み => "`use` を行の頭でない位置に書いている。検査器が取り込みとして読むのは行の頭の `use` だけであり、行の途中の取り込みが持ち込む名前を黙って検査から落とすため、行を改めて行の頭に書く",
        }
    }

    // その行でこの予約語を書いてよい唯一のバイト位置。読み口が読み始める位置と同じ読み飛ばし方をする。
    fn 行の頭の位置(self, 行: &str) -> usize {
        let 残り = match self {
            Self::実装 => {
                let 残り = 先頭の属性を読み飛ばす(行);
                残り.strip_prefix("unsafe").filter(|後ろ| 後ろ.starts_with(char::is_whitespace)).map_or(残り, str::trim_start)
            }
            Self::型の別名 | Self::取り込み => 属性と可視性を読み飛ばす(行),
        };
        行.len().saturating_sub(残り.len())
    }

    // トークン木の外で、この直前の字句の後ろのこの予約語が項目を始めうるか。
    fn 項目を始めうる直前か(self, 直前: 直前の字句) -> bool {
        match self {
            Self::実装 => matches!(直前, 直前の字句::項目の区切り | 直前の字句::予約語のunsafe | 直前の字句::予約語のdefault),
            Self::型の別名 | Self::取り込み => matches!(直前, 直前の字句::項目の区切り | 直前の字句::予約語のpub | 直前の字句::可視性を閉じる丸括弧),
        }
    }
}

/// 項目の予約語の位置を行ごとに読む走査。直前の字句とトークン木の入れ子を行をまたいで覚えるため、1つのファイルを先頭の行から順に読む。
#[derive(Default)]
pub struct 項目の予約語の走査 {
    字句: 予約語の字句の走査,
}

impl 項目の予約語の走査 {
    /// 1行の中の、行の頭でない位置に書いた項目の予約語のうち、違反にするものの一覧。並びは行の中の位置の順である。
    pub fn 行の頭でない項目の予約語一覧(&mut self, 行: &str) -> Vec<項目の予約語> {
        self.字句
            .行を読む(行)
            .into_iter()
            .filter(|現れ| 現れ.位置 != 現れ.予約語.行の頭の位置(行))
            .filter(|現れ| 現れ.トークン木の中か || 現れ.予約語.項目を始めうる直前か(現れ.直前))
            .map(|現れ| 現れ.予約語)
            .collect()
    }
}
