//! Rustのソースに現れる1つの `mod` の宣言。設計オントロジーの一級概念であり、宣言から読める論理のモジュールパスと、中身が在る物理ファイルの両方を自分で答える。
//! 物理のファイルとディレクトリの構造が論理のモジュールの構造と同じ語彙構造を表すという不変条件は、この2つを `module_structure_assertion.rs` が比べて確かめる。
//! `#[path]` の相対パスは、`mod` を宣言しているファイルが置かれているディレクトリを基準にして探す(あるクレートの `src/x.rs` に書いた `#[path = "foo.rs"]` が指すのは `src/foo.rs` であり、`src/x/foo.rs` ではない)。
//! 属性が無い既定の探索が読むのは、宣言元のモジュールの木の下の `<名前>.rs` または `<名前>/mod.rs` である。どちらであっても導かれるモジュールパスは同じであるため、対象の物理ファイルは前者の形で代表させる。
//! 参照: CLAUDE.md「モジュール名・ファイル名・ディレクトリ名の日本語化」。

use std::path::{Path, PathBuf};

use super::module_path::{ソースのファイルの末尾, モジュールパス};

pub struct モジュール宣言 {
    pub 宣言元のファイル: PathBuf,
    pub 行番号: usize, // 違反の報告が指す原文の行。1始まり
    pub モジュール名: String,
    pub 置き場の指定: 置き場の指定,
    pub 本体の形: 本体の形,
}

/// そのモジュールの中身がどこに在るかの指定。
#[derive(Debug, PartialEq, Eq)]
pub enum 置き場の指定 {
    /// `#[path = "..."]` で明示した。日本語のモジュールはこの形を採る
    属性で明示する(String),
    /// 属性が無く、Rustの既定のファイルの探索に任せる
    既定の探索に任せる,
    /// 属性は在るが表記を読めない(属性の行に文字列が無い)。黙って既定の探索とみなさず、この形で観測する
    属性の表記を読めない,
}

/// 宣言の本体が別のファイルに在るか、波括弧の中に在るか。
#[derive(Debug, PartialEq, Eq)]
pub enum 本体の形 {
    別のファイル,
    波括弧の中,
}

impl モジュール宣言 {
    /// 宣言から読める論理のモジュールパス。宣言元のファイルのモジュールパスの下へモジュール名を繋いだものである。
    pub fn 論理のモジュールパス(&self) -> モジュールパス {
        モジュールパス::ファイルのパスから求める(&self.宣言元のファイル).下へ繋ぐ(&[self.モジュール名.as_str()])
    }

    /// 中身が在る物理ファイル。波括弧の中の宣言と、表記を読めない属性の宣言は物理ファイルを持たない。
    pub fn 対象の物理ファイル(&self) -> Option<PathBuf> {
        if self.本体の形 == 本体の形::波括弧の中 {
            return None;
        }
        let 宣言元の置き場からの相対 = match &self.置き場の指定 {
            置き場の指定::属性で明示する(表記) => 表記.replace('\\', "/"),
            置き場の指定::既定の探索に任せる => self.正規形のpath属性の表記(),
            置き場の指定::属性の表記を読めない => return None,
        };
        Some(self.宣言元の置き場().join(宣言元の置き場からの相対))
    }

    /// `#[path]` の正規形の表記。既定の探索が読む位置を、宣言元のファイルの置き場からの相対で書いたものである。
    pub fn 正規形のpath属性の表記(&self) -> String {
        format!("{}{}{}", self.既定の探索の前置き(), self.モジュール名, ソースのファイルの末尾)
    }

    fn 宣言元の置き場(&self) -> &Path {
        self.宣言元のファイル.parent().unwrap_or_else(|| Path::new(""))
    }

    /// 既定の探索が読む位置の前置き。`lib.rs`・`main.rs`・`mod.rs` は自分がモジュールの木の節であるため前置きを持たず、それ以外のファイルは自分の名前のディレクトリを前置きに持つ。
    fn 既定の探索の前置き(&self) -> String {
        let 名前 = self.宣言元のファイル.file_stem().and_then(|名前| 名前.to_str()).unwrap_or_default();
        if matches!(名前, "lib" | "main" | "mod") { String::new() } else { format!("{名前}/") }
    }
}
