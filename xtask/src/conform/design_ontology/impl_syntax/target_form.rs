//! 実装の見出しの対象の型を、検査器が名前で読める形へ固定する純粋な工程。受け取るのはファイルごとのコードだけの行の一覧、返すのは名前で読めない対象を持つ実装の違反一覧である。
//! 違反にするのは3つである。第一に、対象の型の先頭に `::` を書いた実装(`impl 変更 for ::jibun::規則`)である。先頭の `::` のパスは依存のクレートの名前から始まり、`extern crate self as jibun;` と組むと自分のクレートの型を型名で始まらないパスで指せる。
//! 対象の型は裸のパス(識別子と `::` と型引数)で書くと定めており(`name_traceable_form_assertion.rs`)、先頭の `::` はその外である。
//! 第二に、設計解釈マーカーの実装のうち、対象の型のパスの最後の名前を1つの識別子で読めないもの(`impl M不変データ for [規則]`)である。その実装は種にも定義の探索にも入らないため(`syntax_checker.rs` の `トレイト実装型一覧`)、黙って捨てずに違反にする。
//! 第三に、設計解釈マーカーの実装のうち、対象の型を参照か `Pin` で包んだもの(`impl M不変データ for &mut 規則`・`for Pin<&mut 規則>`)である。対象の名前は包みを外した `規則` で読めるため、正規形の検査も純粋データ規約も `規則` の定義を見て通り、可変参照が `M不変データ` を名乗れる。
//! 見出しは `実装の見出しの構文` の1つの読みで分ける。走査範囲の現状はどれも0件である。
//! `クレート構文検査` の説明関数にしないのは、この工程が読むのは実装の見出しだけであり、型の定義も名前の閉包も引かないためである。

use std::path::{Path, PathBuf};

use super::super::super::violation::違反;
use super::super::impl_header::implの見出しを読む;
use super::super::line_matching::名前で読める表記;
use super::super::syntax_patterns::オントロジートレイト;

/// 対象の型を名前で読めない実装の違反一覧。並びはファイルの順、ファイルの中では見出しの書き出しの行の順である。
pub fn 名前で読めない実装の対象の違反一覧(ソース一覧: &[(PathBuf, Vec<String>)]) -> Vec<違反> {
    ソース一覧.iter().flat_map(|(パス, 行一覧)| (0..行一覧.len()).filter_map(move |添字| 見出しの違反(パス, 行一覧, 添字))).collect()
}

// 添字の行が書き出す実装の見出しの対象の型が名前で読めなければ、その違反。
fn 見出しの違反(パス: &Path, 行一覧: &[String], 添字: usize) -> Option<違反> {
    let 構文 = implの見出しを読む(行一覧, 添字)?.構文を読む()?;
    let 表記 = 構文.対象.表記();
    let 説明 = if 表記.starts_with("::") {
        format!(
            "設計オントロジー: 実装の対象の型 `{表記}` の先頭に `::` を書いている。先頭の `::` のパスは `extern crate self as 名前;` と組むと自分のクレートの型を型名で始まらないパスで指せ、検査器が実装の対象の名前を取り違えるため、対象の型は裸のパスで書く。先頭の `::` を外して書く"
        )
    } else if 構文.トレイトの表記().is_some_and(マーカーの名前か) && 構文.対象.参照かpinで包んだか() {
        format!(
            "設計解釈マーカーの実装の対象の型 `{表記}` を参照か `Pin`(`&規則`・`&mut 規則`・`&'a mut 規則`・`Pin<&mut 規則>`)で包んでいる。包まれた型の名前で読むと、可変参照が M不変データ を名乗っても純粋データ規約は包まれた型の定義を見て通り、その可変参照を通した書き換えを検査が見落とすため違反にする。マーカーは型そのものへ実装する"
        )
    } else if 構文.トレイトの表記().is_some_and(マーカーの名前か) && 名前で読める表記(構文.対象.名前()).is_none() {
        format!(
            "設計オントロジー: 設計解釈マーカーの実装の対象の型 `{表記}` のパスの最後の名前を1つの識別子で読めない。検査器はその名前で型の定義をたどり自己変更の検査の種にするため、読めない対象の実装を黙って捨てずに違反にする。対象は型名で終わる裸のパスで書く"
        )
    } else {
        return None;
    };
    Some(違反::行単位(パス.to_path_buf(), 添字 + 1, 説明))
}

// トレイトを書いた位置が、設計解釈マーカーの正規形の名前(`マーカー名` か `blitz_design::マーカー名`)か。
fn マーカーの名前か(位置: &str) -> bool {
    let 名前 = 位置.strip_prefix("blitz_design::").unwrap_or(位置);
    オントロジートレイト::全部の一覧().into_iter().any(|マーカー| マーカー.名前() == 名前)
}

#[cfg(test)]
mod tests {
    use super::super::super::tests::ソース;
    use super::名前で読めない実装の対象の違反一覧;

    fn 説明一覧(本文: &str) -> Vec<String> {
        名前で読めない実装の対象の違反一覧(&[ソース("crates/a/src/x.rs", 本文)]).into_iter().map(|違反| 違反.説明).collect()
    }

    #[test]
    fn 先頭のパスの区切りと名前で始まらないマーカーの対象を違反にする() {
        assert_eq!(説明一覧("impl M不変データ for ::jibun::規則 {}\n").len(), 1);
        assert_eq!(説明一覧("impl M不変データ for::jibun::規則 {}\n").len(), 1);
        assert_eq!(説明一覧("impl 変更 for ::jibun::規則 {}\n").len(), 1);
        assert_eq!(説明一覧("impl M不変データ for [規則] {}\n").len(), 1);
    }

    #[test]
    fn マーカーの対象を参照かpinで包んだ実装を違反にする() {
        for 対象 in ["&規則", "&mut 規則", "&'a mut 規則", "Pin<&mut 規則>", "std::pin::Pin<&mut 規則>", "Pin<Box<規則>>"] {
            let 説明 = 説明一覧(&format!("impl M不変データ for {対象} {{}}\n"));
            assert!(説明.len() == 1 && 説明[0].contains("参照か `Pin`"), "{対象}: {説明:?}");
        }
        assert!(説明一覧("impl 変更 for &mut 規則 {}\n").is_empty());
    }

    #[test]
    fn 名前で始まる対象とマーカーでない実装の名前で始まらない対象は違反にしない() {
        for 本文 in ["impl M不変データ for 規則 {}\n", "impl blitz_design::M不変データ for crate::a::規則<T> {}\n", "impl 変更 for [規則] {}\n", "impl 規則 {}\n"] {
            assert!(説明一覧(本文).is_empty(), "{本文}");
        }
    }
}
