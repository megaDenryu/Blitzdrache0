//! 実装の見出しの型引数より後ろの表記を、宣言(トレイトと対象)と `where` 句に分ける純粋な関数。受け取るのは型引数より後ろの表記、返すのは2つの表記である。

use super::super::declaration_brackets::{最上位で開いた括弧, 見出しの括弧の深さ};
use super::super::identifier_boundary::識別子として現れる位置一覧;

/// 型引数より後ろの表記を、宣言と `where` 句(`where` の後ろから本体を開く `{` か宣言を終える `;` の手前まで)に分ける。どちらも、どの括弧の中でもない位置のものだけで切る。
/// 宣言はトレイトと対象である。`;` で止めるのは、宣言を終える `;` の後ろにある別の項目の `where` を読まないためである。
/// 型引数の定数式(`包み<{ const fn 一() -> usize where u8: Copy { 1 } 一() }, 規則>`)の中の `where` で切ると、対象の表記が途中で途切れるためである。
/// `where` は空白の一致でなく識別子の境界で探す。`規則<T>where T: 境界` のように前に空白の無い形も境界として読むためである。
pub fn 宣言と境界の句に分ける(残り: &str) -> (&str, &str) {
    let mut 括弧 = 見出しの括弧の深さ::default();
    let mut 最上位の位置一覧 = Vec::new();
    let mut 終わり = 残り.len();
    for (位置, 文字) in 残り.char_indices() {
        if 括弧.最上位か() {
            最上位の位置一覧.push(位置);
        }
        if 括弧.一文字読む(文字) == 最上位で開いた括弧::本体の波括弧 || (文字 == ';' && 括弧.最上位か()) {
            終わり = 位置;
            break;
        }
    }
    let 宣言の範囲 = &残り[..終わり];
    match 識別子として現れる位置一覧(宣言の範囲, "where").into_iter().find(|位置| 最上位の位置一覧.contains(位置)) {
        Some(位置) => (宣言の範囲[..位置].trim(), 宣言の範囲[位置 + "where".len()..].trim()),
        None => (宣言の範囲.trim(), ""),
    }
}
