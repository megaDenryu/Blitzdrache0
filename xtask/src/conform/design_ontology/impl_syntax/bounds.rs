//! 見出しの型引数の並びの境界と `where` 句を読んだ値と、名前がそのどこに当たるかの問い。受け取るのは型引数の並び(山括弧の内側)と `where` 句の表記、返すのはこの値である。
//! 実装の見出しと関数の署名が同じ値を使う。`where` 句を切り出す `宣言と境界の句に分ける` も、実装の見出しの型引数より後ろと、関数の引数の並びより後ろの両方を読む。
//! 自己変更の検査は、マーカーの型の名前が対象の表記に現れる実装に加えて、境界でその型を指す実装(`impl<T: DerefMut<Target = 規則>> 変更 for Vec<T>`・`where T: BorrowMut<規則>`)を集める。境界を通すと、本体がマーカーの型の値を書き換えられるためである。
//! 型引数の並びから照らすのは、各引数の名前の後ろの `:` より後ろ(境界と定数の引数の型)だけであり、型引数の名前そのものは照らさない。
//! 実装自身の型引数と同じ名前は、修飾していない裸の現れだけがその実装の中で型引数を指すため、裸の現れは `where` 句でも当たらない(`impl<状態: M状態> 包み<状態> where 状態: Clone`)。
//! 直前が `::` の現れ(`self::規則`・`crate::a::規則`・`super::規則`)は型引数に隠されずモジュールの型を指すため、型引数と同じ名前でも当てる(`impl<T, 規則> 変更<規則> for Vec<T> where T: DerefMut<Target = self::規則>`)。
//! これは名前による近似であり、境界を別のトレイトの宣言か走査範囲の外のトレイトで包んだ形(`trait 取れる: DerefMut<Target = 規則> {}` を経由した `T: 取れる`)は捕まえない。

use super::super::declaration_brackets::{最上位で開いた括弧, 最上位のカンマで分ける, 見出しの括弧の深さ};
use super::super::identifier_boundary::識別子として現れる位置一覧;
use super::super::parameter_form::引数の型の表記;
use super::super::self_modification_evidence::名前が当たった場所;
use super::mutable_borrow_trait::可変の借用を与えるトレイトの型引数が名前を指すか;

/// 見出しの型引数の並びの境界と `where` 句の表記。
pub struct 実装の境界 {
    型引数の並びの境界: String, // 型引数ごとの名前の後ろの `:` より後ろの表記を空白で繋いだもの(`impl<T: Into<地点>, const N: usize>` なら `Into<地点> usize`)
    境界の句: String,           // 山括弧の外の `where` の後ろから本体を開く `{` か宣言を終える `;` の手前までの表記。`where` 句が無ければ空である
}

impl 実装の境界 {
    pub fn 表記から読む(型引数: &str, 境界の句: &str) -> Self {
        Self {
            型引数の並びの境界: 最上位のカンマで分ける(型引数).into_iter().filter_map(|引数| 引数.split_once(':')).map(|(_, 境界)| 境界.trim()).collect::<Vec<_>>().join(" "),
            境界の句: 境界の句.to_string(),
        }
    }

    /// 名前が型引数の並びの境界か `where` 句のどこに識別子の境界で現れるか。名前が型引数に隠されるなら、直前が `::` の現れだけが当たる。
    pub fn 名前が当たった場所(&self, 名前: &str, 型引数に隠されるか: bool) -> Option<名前が当たった場所> {
        [(&self.型引数の並びの境界, 名前が当たった場所::型引数の並びの境界), (&self.境界の句, 名前が当たった場所::境界の句)]
            .into_iter()
            .find_map(|(表記, 場所)| 型引数に隠されない現れがあるか(表記, 名前, 型引数に隠されるか).then_some(場所))
    }

    /// 型引数の並びの境界か `where` 句の、可変の借用を与えるトレイトの型引数が名前を指すか(`U: DerefMut<Target = Self>`)。
    pub fn 可変の借用で名前を指すか(&self, 名前: &str) -> bool {
        [&self.型引数の並びの境界, &self.境界の句].into_iter().any(|表記| 可変の借用を与えるトレイトの型引数が名前を指すか(表記, 名前))
    }

    /// 型引数の並びの境界か `where` 句に、`Fn` 系のトレイトの引数の丸括弧の外で、自分の型(`Self` か型名)への可変参照が字面で現れるか(`I: Iterator<Item = &'a mut Self>`)。規則は引数の型の表記と同じである。
    pub fn 自分の型への可変参照を字面に含むか(&self, 型名: &str) -> bool {
        [&self.型引数の並びの境界, &self.境界の句].into_iter().any(|表記| 引数の型の表記(表記).自分の型への可変参照を含むか(型名))
    }
}

// 表記の中に、名前が型引数に隠されずに識別子の境界で現れるか。型引数に隠される名前なら、直前が `::` の修飾した現れだけを数える。
fn 型引数に隠されない現れがあるか(表記: &str, 名前: &str, 型引数に隠されるか: bool) -> bool {
    識別子として現れる位置一覧(表記, 名前).into_iter().any(|位置| !型引数に隠されるか || 表記[..位置].trim_end().ends_with("::"))
}

/// 型引数より後ろの表記を、宣言と `where` 句(`where` の後ろから本体を開く `{` か宣言を終える `;` の手前まで)に分ける。どちらも、どの括弧の中でもない位置のものだけで切る。
/// 実装の見出しでは宣言はトレイトと対象であり、関数の署名では戻り値の型である。`;` で止めるのは、本体を持たないトレイトの宣言の関数(`fn 変える(&mut self);`)の後ろにある別の関数の `where` を読まないためである。
/// 型引数の定数式(`包み<{ const fn 一() -> usize where u8: Copy { 1 } 一() }, 規則>`)の中の `where` で切ると、対象の表記が途中で途切れ、表記に現れる `規則` を自己変更の検査が見落とすためである。
/// `where` は空白の一致でなく識別子の境界で探す。`規則<T>where T: 境界` のように前に空白の無い形も境界として読むためである。
pub fn 宣言と境界の句に分ける(残り: &str) -> (&str, &str) {
    let mut 括弧 = 見出しの括弧の深さ::default();
    let mut 最上位の位置一覧 = Vec::new();
    let mut 終わり = 残り.len();
    for (位置, 文字) in 残り.char_indices() {
        if 括弧.最上位か() {
            最上位の位置一覧.push(位置);
        }
        if 括弧.一文字読む(文字) == 最上位で開いた括弧::本体の波括弧 || (文字 == ';' && 括弧.最上位か()) {
            終わり = 位置;
            break;
        }
    }
    let 宣言の範囲 = &残り[..終わり];
    match 識別子として現れる位置一覧(宣言の範囲, "where").into_iter().find(|位置| 最上位の位置一覧.contains(位置)) {
        Some(位置) => (宣言の範囲[..位置].trim(), 宣言の範囲[位置 + "where".len()..].trim()),
        None => (宣言の範囲.trim(), ""),
    }
}

#[cfg(test)]
mod tests {
    use super::super::実装の見出しの構文;
    use super::名前が当たった場所;

    // 見出しを読み、名前が境界のどこに当たったか。
    fn 当たった場所(見出し: &str, 名前: &str) -> Option<名前が当たった場所> {
        let 構文 = 実装の見出しの構文::読む(見出し)?;
        構文.境界.名前が当たった場所(名前, 構文.型引数の名前一覧().iter().any(|型引数| 型引数 == 名前))
    }

    #[test]
    fn 型引数の並びの境界と境界の句の名前を見分け型引数の名前とトレイトの型引数と対象は照らさない() {
        assert!(matches!(当たった場所("impl<T: DerefMut<Target = 規則>> 変更 for Vec<T> {", "規則"), Some(名前が当たった場所::型引数の並びの境界)));
        assert!(matches!(当たった場所("impl<T> 変更 for Vec<T> where T: BorrowMut<規則> {", "規則"), Some(名前が当たった場所::境界の句)));
        assert!(matches!(当たった場所("impl<const N: 地点> 変更 for [u8; 1] {", "地点"), Some(名前が当たった場所::型引数の並びの境界)));
        for (見出し, 名前) in [("impl<状態: M状態> 包み<状態> where 状態: Clone {", "状態"), ("impl IndexMut<地点> for 地図 {", "地点"), ("impl 変更 for Vec<規則> {", "規則")] {
            assert!(当たった場所(見出し, 名前).is_none(), "{見出し}");
        }
    }

    #[test]
    fn 型引数と同じ名前でも修飾した現れは当て裸の現れは当てない() {
        assert!(matches!(当たった場所("impl<T, 規則> 変更<規則> for Vec<T> where T: DerefMut<Target = self::規則> {", "規則"), Some(名前が当たった場所::境界の句)));
        assert!(matches!(
            当たった場所("impl<T: DerefMut<Target = crate::a::規則>, 規則> 変更<規則> for Vec<T> {", "規則"),
            Some(名前が当たった場所::型引数の並びの境界)
        ));
        assert!(matches!(当たった場所("impl<T, 規則> 変更 for T where T: DerefMut<Target = super:: 規則> {", "規則"), Some(名前が当たった場所::境界の句)));
        assert!(当たった場所("impl<T, 規則> 変更<規則> for Vec<T> where T: DerefMut<Target = 規則> {", "規則").is_none());
    }
}
