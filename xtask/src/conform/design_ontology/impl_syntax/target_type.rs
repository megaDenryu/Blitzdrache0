//! 実装が対象にする型(`impl` の見出しの ` for ` の後ろか、固有の実装の型の表記)を読んだ値。参照と `Pin` を外した後の型の表記と、外した参照の形を持つ。
//! 対象の型の名前はパスの最後の要素で読む(`crate::a::規則<T>` の名前は `規則`)。先頭の識別子で読むと `crate`・`self` を型名と取り違えるためである。
//! 対象が `&mut X`・`&'a mut X`・`Pin<&mut X>` のときは可変参照を対象にする実装として区別する。その実装の関数は、値で受ける `self` でも `X` を書き換えられるためである。
//! 対象を丸括弧で囲んだ型(`impl 変更 for (規則)`)は、囲みを外した型と同じ型であるため、外してから読む。要素が2つ以上のタプル(`(規則, u8)`)は外さない。
//! 型を包む実装(`Box<規則>`・`Vec<crate::a::規則>`・`Option<規則>`・`[規則]`・`(規則, u8)`・`包み<規則>`)を別に読む口は持たない。
//! 自己変更の検査(`mutable_impl_scan.rs`)が対象の表記に名前が識別子の境界で現れるかを問うため、包まれた型も同じ1つの問いで当たるためである。

use super::super::declaration_brackets::最上位のカンマで分ける;
use super::super::line_matching::{パスの最後の名前, 参照の参照先, 可変参照の参照先};

/// 実装が対象にする型。参照と `Pin` を外した後の型の表記と、外した参照の形を持つ。
pub struct 実装の対象の型 {
    表記: String,
    参照の形: 対象の参照の形,
}

/// 対象の型を読むときに外した参照の形。`Pin<&mut X>` は可変の参照として数える。
#[derive(Clone, Copy, PartialEq, Eq)]
enum 対象の参照の形 {
    参照でない,
    共有の参照,
    可変の参照,
}

impl 実装の対象の型 {
    pub(super) fn 表記から読む(表記: &str) -> Self {
        let 表記 = 丸括弧を外す(表記);
        let (参照先, 参照の形) = match (可変参照の参照先(表記), 参照の参照先(表記), pinの中身(表記).and_then(可変参照の参照先)) {
            (Some(参照先), _, _) | (None, None, Some(参照先)) => (参照先, 対象の参照の形::可変の参照),
            (None, Some(参照先), _) => (参照先, 対象の参照の形::共有の参照),
            (None, None, None) => (表記, 対象の参照の形::参照でない),
        };
        Self {
            表記: 丸括弧を外す(参照先).to_string(),
            参照の形,
        }
    }

    /// 可変参照(`&mut X`・`&'a mut X`・`Pin<&mut X>`)を対象にする実装か。その実装の関数は、値で受ける `self` でも `X` を書き換えられる。
    pub fn 可変参照か(&self) -> bool {
        self.参照の形 == 対象の参照の形::可変の参照
    }

    /// 対象を参照か `Pin` で包んで書いた実装か。外した参照があるときと、外せなかった `Pin<..>`(`Pin<&規則>`・`Pin<Box<規則>>`)の名前が `Pin` のときである。
    pub fn 参照かpinで包んだか(&self) -> bool {
        self.参照の形 != 対象の参照の形::参照でない || self.名前() == "Pin"
    }

    /// 参照と `Pin<..>` と囲みの丸括弧を、外せなくなるまで繰り返し外した表記(`&mut &mut T`・`Pin<&mut T>`・`&(T)` なら `T`)。全称の実装の判定が使う。
    pub fn 参照とpinを外しきった表記(&self) -> &str {
        let mut 表記 = self.表記.as_str();
        while let Some(中) = 参照の参照先(表記).or_else(|| pinの中身(表記)) {
            表記 = 丸括弧を外す(中);
        }
        表記
    }

    /// 参照と `Pin` と囲みの丸括弧を外した後の型の表記そのもの。名前の閉包の検査が、この表記にマーカーの名前が識別子として現れるかを問う。
    pub fn 表記(&self) -> &str {
        &self.表記
    }

    /// 型のパスの最後の要素の名前。定義をたどる鍵である。
    pub fn 名前(&self) -> &str {
        パスの最後の名前(&self.表記)
    }
}

// 表記を囲む丸括弧を、中が1つの型である限り外す(`((規則))` は `規則`)。単位型 `()` とタプルは外さない。
fn 丸括弧を外す(表記: &str) -> &str {
    let mut 表記 = 表記.trim();
    while let Some(中) = 表記.strip_prefix('(').and_then(|残り| 残り.strip_suffix(')')) {
        if 中.trim().is_empty() || 最上位のカンマで分ける(中).len() > 1 {
            break;
        }
        表記 = 中.trim();
    }
    表記
}

// `Pin<X>`(`std::pin::Pin<X>` を含む)の中身 `X`。`Pin` でなければ無い。
fn pinの中身(表記: &str) -> Option<&str> {
    let (パス, 残り) = 表記.split_once('<')?;
    if パスの最後の名前(パス) != "Pin" {
        return None;
    }
    残り.strip_suffix('>')
}
