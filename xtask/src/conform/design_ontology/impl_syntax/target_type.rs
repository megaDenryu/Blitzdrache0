//! 実装が対象にする型(`impl` の見出しの ` for ` の後ろか、固有の実装の型の表記)を読んだ値。参照と `Pin` を外した後の型の表記と、表記の全体が含む参照の形を持つ。
//! 対象の型の名前はパスの最後の要素で読む(`crate::a::規則<T>` の名前は `規則`)。先頭の識別子で読むと `crate`・`self` を型名と取り違えるためである。
//! 対象の表記のどの深さにでも可変参照(`&mut X`・`&'a mut X`。`Pin<&mut X>` を含む)が現れる実装は、可変参照を対象にする実装として区別する。
//! その実装の関数は、値で受ける `self` でも `X` を書き換えられるためである(`impl 変更 for Option<&mut 規則> { fn 変える(self) { .. } }`)。一番外側だけで判定すると、型引数や組の中の可変参照を見落とす。
//! 対象を丸括弧で囲んだ型(`impl 変更 for (規則)`)は、囲みを外した型と同じ型であるため、外してから読む。要素が2つ以上のタプル(`(規則, u8)`)は外さない。
//! 型を包む実装(`Box<規則>`・`Vec<crate::a::規則>`・`Option<規則>`・`[規則]`・`(規則, u8)`・`包み<規則>`)を別に読む口は持たない。
//! 自己変更の検査(`mutable_impl_scan.rs`)が対象の表記に名前が識別子の境界で現れるかを問うため、包まれた型も同じ1つの問いで当たるためである。

use super::super::declaration_brackets::最上位のカンマで分ける;
use super::super::identifier_boundary::識別子として現れるか;
use super::super::line_matching::{パスの最後の名前, 参照の参照先, 可変参照の参照先};

/// 実装が対象にする型。参照と `Pin` を外した後の型の表記と、表記の全体が含む参照の形を持つ。
pub struct 実装の対象の型 {
    表記: String,
    含む参照: 表記が含む参照,
}

/// 対象の型の表記の全体(どの深さでも)が含む参照の形。`Pin<&mut X>` は可変参照を含む。
#[derive(Clone, Copy, PartialEq, Eq)]
enum 表記が含む参照 {
    参照もpinも含まない,
    共有の参照かpinを含む,
    可変参照を含む,
}

impl 実装の対象の型 {
    pub(super) fn 表記から読む(表記: &str) -> Self {
        let 表記 = 丸括弧を外す(表記);
        let 参照先 = 参照の参照先(表記).or_else(|| pinの中身(表記).and_then(可変参照の参照先)).unwrap_or(表記);
        Self {
            表記: 丸括弧を外す(参照先).to_string(),
            含む参照: 表記が含む参照::表記の全体から読む(表記),
        }
    }

    /// 対象の表記のどの深さにでも可変参照(`&mut X`・`&'a mut X`・`Pin<&mut X>`・`Option<&mut X>`)が現れる実装か。その実装の関数は、値で受ける `self` でも `X` を書き換えられる。
    pub fn 可変参照か(&self) -> bool {
        self.含む参照 == 表記が含む参照::可変参照を含む
    }

    /// 対象の表記のどの深さにでも参照か `Pin` が現れる実装か(`&規則`・`Pin<Box<規則>>`・`包み<&mut 規則>`・`Box<&規則>`)。
    pub fn 参照かpinで包んだか(&self) -> bool {
        self.含む参照 != 表記が含む参照::参照もpinも含まない
    }

    /// 参照と `Pin<..>` と囲みの丸括弧を、外せなくなるまで繰り返し外した表記(`&mut &mut T`・`Pin<&mut T>`・`&(T)` なら `T`)。全称の実装の判定が使う。
    pub fn 参照とpinを外しきった表記(&self) -> &str {
        let mut 表記 = self.表記.as_str();
        while let Some(中) = 参照の参照先(表記).or_else(|| pinの中身(表記)) {
            表記 = 丸括弧を外す(中);
        }
        表記
    }

    /// 参照と `Pin` と囲みの丸括弧を外した後の型の表記そのもの。名前の閉包の検査が、この表記にマーカーの名前が識別子として現れるかを問う。
    pub fn 表記(&self) -> &str {
        &self.表記
    }

    /// 型のパスの最後の要素の名前。定義をたどる鍵である。
    pub fn 名前(&self) -> &str {
        パスの最後の名前(&self.表記)
    }
}

impl 表記が含む参照 {
    // 表記の全体から読む。可変参照は `&` の位置ごとに可変参照の型の書き出しか(`&` と寿命の後ろが `mut` と空白)で数え、`Pin` は識別子の境界で数える。
    fn 表記の全体から読む(表記: &str) -> Self {
        if 表記.match_indices('&').any(|(位置, _)| 可変参照の参照先(&表記[位置..]).is_some()) {
            Self::可変参照を含む
        } else if 表記.contains('&') || 識別子として現れるか(表記, "Pin") {
            Self::共有の参照かpinを含む
        } else {
            Self::参照もpinも含まない
        }
    }
}

// 表記を囲む丸括弧を、中が1つの型である限り外す(`((規則))` は `規則`)。単位型 `()` とタプルは外さない。
fn 丸括弧を外す(表記: &str) -> &str {
    let mut 表記 = 表記.trim();
    while let Some(中) = 表記.strip_prefix('(').and_then(|残り| 残り.strip_suffix(')')) {
        if 中.trim().is_empty() || 最上位のカンマで分ける(中).len() > 1 {
            break;
        }
        表記 = 中.trim();
    }
    表記
}

// `Pin<X>`(`std::pin::Pin<X>` を含む)の中身 `X`。`Pin` でなければ無い。
fn pinの中身(表記: &str) -> Option<&str> {
    let (パス, 残り) = 表記.split_once('<')?;
    if パスの最後の名前(パス) != "Pin" {
        return None;
    }
    残り.strip_suffix('>')
}
