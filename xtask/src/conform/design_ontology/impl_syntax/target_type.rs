//! 実装が対象にする型(`impl` の見出しの ` for ` の後ろか、固有の実装の型の表記)を読んだ値。参照と `Pin` を外した後の型の表記と、可変参照を対象にするかを持つ。
//! 対象の型の名前はパスの最後の要素で読む(`crate::a::規則<T>` の名前は `規則`)。先頭の識別子で読むと `crate`・`self` を型名と取り違えるためである。
//! 対象が `&mut X`・`&'a mut X`・`Pin<&mut X>` のときは可変参照を対象にする実装として区別する。その実装の関数は、値で受ける `self` でも `X` を書き換えられるためである。
//! 対象を丸括弧で囲んだ型(`impl 変更 for (規則)`)は、囲みを外した型と同じ型であるため、外してから読む。要素が2つ以上のタプル(`(規則, u8)`)は外さない。
//! 型を包む実装とは、対象の型のパスの最後の名前は型名でないが、対象の型の表記の中に型名が識別子として現れる実装のことである(`Box<規則>`・`Vec<crate::a::規則>`・`Option<規則>`・`[規則]`・`(規則, u8)`・`包み<規則>`)。
//! その実装の可変の受け手(`&mut Vec<規則>`)は包まれた型の値を書き換えうる。定義のモジュールにあれば私有のフィールドにも届くため、自己変更の検査(`mutable_impl_scan.rs`)が型に属する実装と同じく読む。

use super::super::declaration_brackets::最上位のカンマで分ける;
use super::super::line_matching::{パスの修飾, パスの最後の名前, 参照の参照先, 可変参照の参照先};

/// 実装が対象にする型。参照と `Pin` を外した後の型の表記と、可変参照を対象にするかを持つ。
pub struct 実装の対象の型 {
    表記: String,
    pub 可変参照か: bool,
}

impl 実装の対象の型 {
    pub(super) fn 表記から読む(表記: &str) -> Self {
        let 表記 = 丸括弧を外す(表記);
        let (参照先, 可変参照か) = match (可変参照の参照先(表記), 参照の参照先(表記), pinの中身(表記).and_then(可変参照の参照先)) {
            (Some(参照先), _, _) | (None, None, Some(参照先)) => (参照先, true),
            (None, Some(参照先), _) => (参照先, false),
            (None, None, None) => (表記, false),
        };
        Self {
            表記: 丸括弧を外す(参照先).to_string(),
            可変参照か,
        }
    }

    /// 参照と `Pin` と囲みの丸括弧を外した後の型の表記そのもの。名前の閉包の検査が、この表記にマーカーの名前が識別子として現れるかを問う。
    pub fn 表記(&self) -> &str {
        &self.表記
    }

    /// 型のパスの最後の要素の名前。定義をたどる鍵である。
    pub fn 名前(&self) -> &str {
        パスの最後の名前(&self.表記)
    }

    /// 型のパスの最後の要素より前の修飾(`crate::a::規則` なら `crate::a`)。修飾の無い型名だけの表記なら無い。
    pub fn パスの修飾(&self) -> Option<&str> {
        パスの修飾(&self.表記)
    }

    /// 型を包む実装(`impl 変更 for Vec<規則>`)なら、包まれた型を対象の型として読んだ値の全部。可変参照を対象にするかは包む側から引き継ぐ。
    /// 表記の中に型名を名乗るパスが複数あれば(`(甲::規則, 乙::規則)`)、全部を返す。どれか1つだけを結び付けると、別のパスが指す検査している型を落とすためである。
    /// 対象の型のパスの最後の名前が型名なら包んでいないため空である。
    pub fn 包まれた型一覧(&self, 型名: &str) -> Vec<Self> {
        if self.名前() == 型名 {
            return Vec::new();
        }
        型名を名乗る中のパス一覧(&self.表記, 型名)
            .map(|パス| Self {
                表記: パス.to_string(),
                可変参照か: self.可変参照か,
            })
            .collect()
    }
}

// 表記を囲む丸括弧を、中が1つの型である限り外す(`((規則))` は `規則`)。単位型 `()` とタプルは外さない。
fn 丸括弧を外す(表記: &str) -> &str {
    let mut 表記 = 表記.trim();
    while let Some(中) = 表記.strip_prefix('(').and_then(|残り| 残り.strip_suffix(')')) {
        if 中.trim().is_empty() || 最上位のカンマで分ける(中).len() > 1 {
            break;
        }
        表記 = 中.trim();
    }
    表記
}

// `Pin<X>`(`std::pin::Pin<X>` を含む)の中身 `X`。`Pin` でなければ無い。
fn pinの中身(表記: &str) -> Option<&str> {
    let (パス, 残り) = 表記.split_once('<')?;
    if パスの最後の名前(パス) != "Pin" {
        return None;
    }
    残り.strip_suffix('>')
}

// 表記の中の型のパス(識別子と `::` の並び)のうち、最後の名前が型名であるものの全部。表記の最上位のパス(対象の型そのもの)は呼び出し側が除く。
fn 型名を名乗る中のパス一覧<'a>(表記: &'a str, 型名: &'a str) -> impl Iterator<Item = &'a str> {
    パスの一覧(表記).filter(move |パス| パス.rsplit("::").next().is_some_and(|最後の名前| 最後の名前 == 型名))
}

// 表記の中の型のパスを順に返す。パスとは、識別子の文字(英数字・下線・非ASCIIの文字)と `:` が続く並びであり、前後の `:` を除いたものである。
fn パスの一覧(表記: &str) -> impl Iterator<Item = &str> {
    表記.split(|文字: char| !(文字.is_alphanumeric() || 文字 == '_' || 文字 == ':')).map(|パス| パス.trim_matches(':')).filter(|パス| !パス.is_empty())
}

#[cfg(test)]
mod tests {
    use super::型名を名乗る中のパス一覧;

    #[test]
    fn 包む型の表記の中の型名のパスを全部取り出す() {
        for (表記, 中のパス) in [("Box<規則>", "規則"), ("Vec<crate::a::規則>", "crate::a::規則"), ("[規則]", "規則"), ("(規則, u8)", "規則"), ("Option<&'a 規則>", "規則")] {
            assert_eq!(型名を名乗る中のパス一覧(表記, "規則").collect::<Vec<_>>(), [中のパス], "{表記}");
        }
        assert_eq!(型名を名乗る中のパス一覧("(甲::規則, 乙::規則)", "規則").collect::<Vec<_>>(), ["甲::規則", "乙::規則"]);
        assert_eq!(型名を名乗る中のパス一覧("Vec<規則の一覧>", "規則").count(), 0);
    }
}
