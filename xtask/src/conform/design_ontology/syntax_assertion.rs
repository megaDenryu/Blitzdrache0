//! `クレート構文検査` の説明関数群。各関数は1つの設計規則を検査し、破れを `違反一覧` へ溜めて `self` を返す(メソッドチェーン)。
//! 型の定義が見つからない実装と、同名の定義が複数のファイルにあって一意に決まらない実装と、`use` の別名のため取り込み元を求められない実装は、その規則の違反でなく別の違反にする。黙って通さない。

use super::super::violation::違反;
use super::mutable_impl_scan::{検査する型の定義, 自己変更の検査};
use super::self_modification_evidence::自己変更の根拠;
use super::syntax_checker::クレート構文検査;
use super::syntax_patterns::{Rust型種別, オントロジートレイト};
use super::trait_implementation::トレイト実装型;
use super::type_definition::定義ブロックの結果;
use super::unbound_implementation_ledger::対象の型を決められない実装の台帳;

impl クレート構文検査 {
    pub fn すべてのコマンドが列挙型であること(self) -> Self {
        let 型一覧 = self.トレイト実装型一覧(オントロジートレイト::Mコマンド);
        self.すべての型が型種別を満たすこと(オントロジートレイト::Mコマンド, Rust型種別::Enum, 型一覧)
    }

    pub fn すべての規則が構造体であること(self) -> Self {
        let 型一覧 = self.トレイト実装型一覧(オントロジートレイト::M規則);
        self.すべての型が型種別を満たすこと(オントロジートレイト::M規則, Rust型種別::Struct, 型一覧)
    }

    /// `M結果` を実装する型が `enum` であること(結果は排他的な帰結を表す判別型であり、結果の値を束ねた `struct` は `M結果` になれない)。
    /// 正本 `blitz_design` の `marker.rs` が持つ完全に修飾した `std::result::Result` への包括の実装だけを定義をたどらない特例として飛ばし、他の実装は対象の型名が `Result` でも定義をたどる。`enum` が処理の帰結を表しているかという意味の法則はここでは判定しない。
    pub fn すべての結果が列挙型であること(self) -> Self {
        let 型一覧 = self.トレイト実装型一覧(オントロジートレイト::M結果).into_iter().filter(|型| !型.正本の標準resultへの包括の実装か()).collect();
        self.すべての型が型種別を満たすこと(オントロジートレイト::M結果, Rust型種別::Enum, 型一覧)
    }

    /// `M不変データ` またはデータの役割のいずれかを実装する型の定義が、参照・生ポインタ・内部可変性を持たないこと。
    /// 役割の実装から型の定義をたどって当てるため、`impl M不変データ for` の置き場所を問わない。同じ型が複数の役割を持っても違反は1回だけ報告する。
    pub fn すべての純粋データが参照と内部可変性を持たないこと(mut self) -> Self {
        for (トレイト, 型) in self.純粋データ規約の対象一覧() {
            if self.定義が見つからなければ違反にする(トレイト, &型) {
                continue;
            }
            for 説明 in self.純粋データの規約の違反一覧(&型) {
                self.違反にする(トレイト, &型, 説明);
            }
        }
        self
    }

    /// `M不変データ` を実装する型の固有の `impl` とトレイトの実装の本体の直下の関数が、受け手と引数に自分の型への可変参照を持たないこと(自己変更の禁止。規則は `mutable_impl_scan.rs`)。
    /// データの役割(`M状態`・`Mコマンド`・`Mイベント`・`M規則`・`M入力`・`M観測`)を実装する型はすべて `M不変データ` も実装するため、この1つの検査が役割ごとの検査を兼ねる。
    pub fn すべての不変データが可変参照メソッドを持たないこと(mut self) -> Self {
        let 破れ一覧: Vec<(トレイト実装型, 自己変更の根拠)> = {
            let 検査 = 自己変更の検査::生成する(&self.ソース一覧);
            self.トレイト実装型一覧(オントロジートレイト::M不変データ)
                .into_iter()
                .filter_map(|型| {
                    let 定義ブロックの結果::見つかった { モジュール, .. } = self.型の定義ブロック(&型) else {
                        return None;
                    };
                    let 根拠 = 検査.最初の自己変更の根拠(&検査する型の定義 {
                        型名: &型.型名, 定義のモジュール: &モジュール
                    })?;
                    Some((型, 根拠))
                })
                .collect()
        };
        for (型, 根拠) in 破れ一覧 {
            self.違反にする(オントロジートレイト::M不変データ, &型, 根拠.説明());
        }
        self
    }

    /// 対象の型を決められない実装(全称の実装とマクロの本体の中の実装)が自己変更を与える関数を持たないこと。持つなら台帳に理由が載っていること。台帳の行の陳腐化も違反にする。
    /// 台帳を引数で受けるのは、試験が行を与えた台帳で除外と陳腐化を確かめるためである。
    pub fn 対象の型を決められない実装が自己変更を与えないこと(mut self, 台帳: &対象の型を決められない実装の台帳) -> Self {
        let 検出一覧 = 自己変更の検査::生成する(&self.ソース一覧).対象の型を決められない自己変更の実装一覧();
        self.違反一覧.extend(台帳.突き合わせる(&検出一覧));
        self
    }

    // 型一覧を引数で受けるのは、`M結果` が正本の包括の実装を除いた一覧を渡すためである。
    fn すべての型が型種別を満たすこと(mut self, トレイト: オントロジートレイト, 種別: Rust型種別, 型一覧: Vec<トレイト実装型>) -> Self {
        for 型 in 型一覧 {
            if self.定義が見つからなければ違反にする(トレイト, &型) || self.型種別を満たしているか(種別, &型) {
                continue;
            }
            self.違反にする(トレイト, &型, format!("は {} 定義が必要です", 種別.キーワード()));
        }
        self
    }

    // 定義が見つからないときと、同名の定義が複数のファイルにあって一意に決まらないときを別の違反にする。真なら呼び出し側はその型の検査を打ち切る。
    pub(super) fn 定義が見つからなければ違反にする(&mut self, トレイト: オントロジートレイト, 型: &トレイト実装型) -> bool {
        let 説明 = match self.型の定義ブロック(型) {
            定義ブロックの結果::見つかった { .. } => return false,
            定義ブロックの結果::見つからない => "の定義(struct/enum)が見つかりません",
            定義ブロックの結果::複数ある => "の同名の定義が複数あり一意に決まらない(同じファイルの中か、複数のファイルにある。実装と同じファイルに定義を1つだけ置くか、use で定義のモジュールパスを取り込む)",
            定義ブロックの結果::別名のため取り込み元を求められない => "の use の別名(as)からは取り込み元を求められない(別名を付けずに取り込む)",
        };
        self.違反にする(トレイト, 型, 説明.to_string());
        true
    }

    pub(super) fn 違反にする(&mut self, トレイト: オントロジートレイト, 型: &トレイト実装型, 説明: String) {
        let 説明 = format!("設計オントロジー: {} `{}` {}", トレイト.名前(), 型.型名, 説明);
        self.違反一覧.push(違反::行単位(型.パス.clone(), 型.行番号, 説明));
    }
}
