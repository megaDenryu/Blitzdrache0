//! `クレート構文検査` の説明関数群。各関数は1つの設計規則を検査し、破れを `違反一覧` へ溜めて `self` を返す(メソッドチェーン)。
//! 型の定義が見つからない実装と、同名の定義が複数のファイルにあって一意に決まらない実装は、その規則の違反でなく別の違反にする。黙って通さない。

use super::super::violation::違反;
use super::syntax_checker::{クレート構文検査, トレイト実装型};
use super::syntax_patterns::{Rust型種別, オントロジートレイト};
use super::type_definition::定義ブロックの結果;

impl クレート構文検査 {
    pub fn すべてのコマンドが列挙型であること(self) -> Self {
        self.すべての型が型種別を満たすこと(オントロジートレイト::Mコマンド, Rust型種別::Enum)
    }

    pub fn すべての規則が構造体であること(self) -> Self {
        self.すべての型が型種別を満たすこと(オントロジートレイト::M規則, Rust型種別::Struct)
    }

    pub fn すべてのmdtoが純粋データ規約を満たすこと(self) -> Self {
        self.すべての型が純粋データ規約を満たすこと(オントロジートレイト::MDTO)
    }

    pub fn すべてのイベントが純粋データ規約を満たすこと(self) -> Self {
        self.すべての型が純粋データ規約を満たすこと(オントロジートレイト::Mイベント)
    }

    pub fn すべてのコマンドが可変参照メソッドを持たないこと(self) -> Self {
        self.すべての型が可変参照メソッドを持たないこと(オントロジートレイト::Mコマンド)
    }

    pub fn すべてのイベントが可変参照メソッドを持たないこと(self) -> Self {
        self.すべての型が可変参照メソッドを持たないこと(オントロジートレイト::Mイベント)
    }

    pub fn すべての規則が可変参照メソッドを持たないこと(self) -> Self {
        self.すべての型が可変参照メソッドを持たないこと(オントロジートレイト::M規則)
    }

    fn すべての型が型種別を満たすこと(mut self, トレイト: オントロジートレイト, 種別: Rust型種別) -> Self {
        for 型 in self.トレイト実装型一覧(トレイト) {
            if self.定義が見つからなければ違反にする(トレイト, &型) || self.型種別を満たしているか(種別, &型) {
                continue;
            }
            self.違反にする(トレイト, &型, format!("は {} 定義が必要です", 種別.キーワード()));
        }
        self
    }

    fn すべての型が純粋データ規約を満たすこと(mut self, トレイト: オントロジートレイト) -> Self {
        for 型 in self.トレイト実装型一覧(トレイト) {
            if self.定義が見つからなければ違反にする(トレイト, &型) {
                continue;
            }
            for 説明 in self.dto純粋性違反一覧(&型) {
                self.違反にする(トレイト, &型, 説明);
            }
        }
        self
    }

    fn すべての型が可変参照メソッドを持たないこと(mut self, トレイト: オントロジートレイト) -> Self {
        for 型 in self.トレイト実装型一覧(トレイト) {
            if self.可変参照メソッドを含むか(&型.型名) {
                self.違反にする(トレイト, &型, "は &mut self メソッドを持てません".to_string());
            }
        }
        self
    }

    // 定義が見つからないときと、同名の定義が複数のファイルにあって一意に決まらないときを別の違反にする。真なら呼び出し側はその型の検査を打ち切る。
    fn 定義が見つからなければ違反にする(&mut self, トレイト: オントロジートレイト, 型: &トレイト実装型) -> bool {
        let 説明 = match self.型の定義ブロック(型) {
            定義ブロックの結果::見つかった(_) => return false,
            定義ブロックの結果::見つからない => "の定義(struct/enum)が見つかりません",
            定義ブロックの結果::複数ある => "の同名の定義が複数のファイルにあり一意に決まらない(実装と同じファイルに定義を置く)",
        };
        self.違反にする(トレイト, 型, 説明.to_string());
        true
    }

    fn 違反にする(&mut self, トレイト: オントロジートレイト, 型: &トレイト実装型, 説明: String) {
        let 説明 = format!("設計オントロジー: {} `{}` {}", トレイト.名前(), 型.型名, 説明);
        self.違反一覧.push(違反::行単位(型.パス.clone(), 型.行番号, 説明));
    }
}
