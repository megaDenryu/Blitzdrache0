//! `クレート構文検査` の説明関数のうち、`MParameter` を名乗る構造体のフィールドがどれも `Mコマンド` を名乗る型であれば違反にするもの。
//! `Mコマンド` だけを名前付きのフィールドに並べた構造体は、定義により `M命令の組` であり、遷移の役割のコマンドの位置へ入れる命令である(設計オントロジー第2節・2.6節)。
//! `MParameter` はコマンドの位置へ入れない必須入力の束であるため、この形の型が `MParameter` を名乗るのは取り違えである。
//! 2026-09-28 に、Esca の `経路の開閉と旅行者の歩行の更新への入力` がこの形のまま `MParameter` を名乗り、実際にこの取り違えが起きたため、形を機械で捕まえる。
//! `M命令の組` も名乗る型は、排他の検査(`分類の排他と網羅の検査.rs`)が報告するため、ここでは報告しない。フィールドを読めない型と、フィールドを持たない型は、コマンドだけを並べた形と確かめられないため違反にしない。

use std::collections::HashSet;

use super::syntax_checker::クレート構文検査;
use super::設計解釈マーカーの一覧::設計解釈マーカー;

const コマンドだけを並べた違反: &str =
    "のフィールドはどれも `Mコマンド` を名乗る型である。`Mコマンド` だけを名前付きのフィールドに並べた構造体は遷移の役割のコマンドの位置へ入れる命令の組であり、`MParameter` でなく `M遷移が受け取る命令` と `M命令の組` を名乗る";

impl クレート構文検査 {
    /// `MParameter` を名乗る構造体のフィールドが、どれも `Mコマンド` を名乗る型でないこと。
    pub fn コマンドだけを並べた構造体が必須入力の束を名乗っていないこと(mut self) -> Self {
        let コマンドの同一性一覧 = self.コマンドの同一性一覧();
        let 命令の組の同一性一覧: HashSet<_> = self.設計解釈マーカーの実装一覧(設計解釈マーカー::M命令の組).iter().map(|型| self.型の同一性(型)).collect();
        for 型 in self.設計解釈マーカーの実装一覧(設計解釈マーカー::MParameter) {
            if 命令の組の同一性一覧.contains(&self.型の同一性(&型)) {
                continue;
            }
            if self.構造体のフィールドを読む(&型, &コマンドの同一性一覧).どのフィールドもコマンドか() {
                self.違反にする(&型, コマンドだけを並べた違反.to_string());
            }
        }
        self
    }
}
