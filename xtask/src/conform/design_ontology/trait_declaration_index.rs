//! 走査範囲のトレイトの宣言を名前で引く索引。全ソースから1度だけ組み、名前ごとに、宣言の本体の直下の関数の署名の一覧と、本体の直下で呼んだマクロと、同名の宣言の件数を持つ。
//! 名前だけで引くのは過大近似である。同じクレートの `甲::変更` と `乙::変更` を区別せず、どちらか1つでも自己変更を与える関数を持てば与えると答える。
//! パスを解いて宣言を1つに決める形をやめたのは、`use`・glob・再公開・別名・cfg・局所の項目・波括弧付きのモジュール・マクロの呼び出しの中を解く解き方に、名前を取りこぼす穴が繰り返し見つかったためである。
//! 索引へ入れる宣言の位置を限らないのも同じ理由である。関数の本体の中の宣言もマクロの本体の中の宣言も同じ名前として数える。位置で絞ると、絞った位置の宣言が検査から漏れる。
//! 本体の直下のマクロの呼び出し(`body_macro_invocation.rs`)を持つのは、マクロがトレイトの既定の関数を生やせるのに、検査器がマクロを展開できず、生えた関数の署名を読めないためである。
//! 読む見出しは `trait`・`pub trait`・`pub(crate) trait`・`unsafe trait`・`pub unsafe trait` と、型引数・`where`・上位トレイトを持つものであり、前に同じ行で属性(`#[..] trait`)を書いてもよい。既定の関数の `where Self: Sized` も除外しない。
//! 見出しの行からトレイトの名前を読むのは `trait_name_index.rs` である。上位トレイトは辿らない。`impl 下位 for 型` が成り立つには `型: 上位` が要り、それは明示の `impl 上位 for 型`(型に属する実装として別に読む)か全称の実装(対象の型を決められない実装として別に読む)でしか満たせないためである。
//! 走査範囲の外のトレイト(std と依存クレート)は索引に無い。索引に無い名前は、走査範囲に宣言が1件も無いため、呼び出し側(`implemented_trait.rs`)はその実装を検査しない。

use std::collections::HashMap;
use std::path::PathBuf;

use super::body_macro_invocation::本体の直下のマクロの呼び出し;
use super::function_signature::{本体の直下の関数の署名一覧, 自己変更を問う対象, 関数の署名};
use super::impl_header::宣言の見出しを読む;
use super::trait_name_index::トレイトの宣言の名前;

// 1つの名前のトレイトの宣言の中身。同名の宣言が複数あれば、関数を1つの列へ連ねる(関数を1つも持たない宣言も件数に数える)。
#[derive(Default)]
struct トレイトの宣言の中身 {
    関数一覧: Vec<関数の署名>,
    本体の直下のマクロ: Option<String>, // 本体の直下で最初に呼んだマクロの名前
    宣言の件数: usize,
}

#[derive(Default)]
pub struct トレイトの宣言の索引 {
    名前ごとの中身: HashMap<String, トレイトの宣言の中身>,
}

impl トレイトの宣言の索引 {
    pub fn 全ソースから組む(ソース一覧: &[(PathBuf, Vec<String>)]) -> Self {
        let mut 索引 = Self::default();
        for (_, 行一覧) in ソース一覧 {
            for (開始, 行) in 行一覧.iter().enumerate() {
                let Some((名前, 見出し)) = トレイトの宣言の名前(行).zip(宣言の見出しを読む(行一覧, 開始)) else {
                    continue;
                };
                let 本体 = 見出し.本体の文字列(行一覧);
                let 中身 = 索引.名前ごとの中身.entry(名前).or_default();
                中身.関数一覧.extend(本体の直下の関数の署名一覧(&本体));
                中身.本体の直下のマクロ = 中身.本体の直下のマクロ.take().or_else(|| 本体の直下のマクロの呼び出し(&本体));
                中身.宣言の件数 += 1;
            }
        }
        索引
    }

    /// 閉包の名前の並びで引いた宣言の関数の全部。関数の署名の境界に閉じた名前が現れる関数を探す問い(`mutable_impl_scan/signature_bound_question.rs`)が照らす。
    pub fn 名前で引いた関数一覧<'a>(&'a self, 名前一覧: &'a [String]) -> impl Iterator<Item = 引いた宣言の関数<'a>> {
        名前一覧.iter().filter_map(|名前| self.名前ごとの中身.get(名前).map(|中身| (名前, 中身))).flat_map(|(名前, 中身)| {
            中身.関数一覧.iter().map(move |関数| 引いた宣言の関数 {
                トレイト名: 名前,
                同名の宣言の件数: 中身.宣言の件数,
                関数,
            })
        })
    }

    /// 閉包の名前の並びで宣言を引き、対象へ自己変更を与える関数を宣言しているかと、宣言を完全に読めるかを答える。
    pub fn 宣言を参照する(&self, 名前一覧: &[String], 対象: &自己変更を問う対象) -> トレイトの宣言を参照した結果 {
        let 引いた中身一覧: Vec<(&String, &トレイトの宣言の中身)> = 名前一覧.iter().filter_map(|名前| self.名前ごとの中身.get(名前).map(|中身| (名前, 中身))).collect();
        for (名前, 中身) in &引いた中身一覧 {
            if let Some(関数) = 中身.関数一覧.iter().find(|関数| 対象.自己変更を与えるか(関数)) {
                return トレイトの宣言を参照した結果::自己変更を与える {
                    トレイト名: (*名前).to_string(),
                    関数名: 関数.名前.clone(),
                    同名の宣言の件数: 中身.宣言の件数,
                };
            }
        }
        for (名前, 中身) in &引いた中身一覧 {
            if let Some(マクロ名) = 中身.本体の直下のマクロ.clone() {
                return トレイトの宣言を参照した結果::宣言を完全に読めない {
                    トレイト名: (*名前).to_string(), マクロ名
                };
            }
        }
        if 引いた中身一覧.is_empty() {
            トレイトの宣言を参照した結果::宣言が無い
        } else {
            トレイトの宣言を参照した結果::自己変更を与えない
        }
    }
}

/// 名前で引いた宣言の関数1つ。引いたトレイトの名前と、その名前の宣言の件数と組にする。
pub struct 引いた宣言の関数<'a> {
    pub トレイト名: &'a str,
    pub 同名の宣言の件数: usize,
    pub 関数: &'a 関数の署名,
}

/// トレイトの名前で走査範囲の宣言を参照した結果。
pub enum トレイトの宣言を参照した結果 {
    宣言が無い,
    自己変更を与えない,
    自己変更を与える { トレイト名: String, 関数名: String, 同名の宣言の件数: usize },
    宣言を完全に読めない { トレイト名: String, マクロ名: String }, // 宣言の本体の直下で呼んだマクロが生やす関数を読めない
}
