//! 走査範囲のトレイトの宣言を、宣言のモジュールパスと名前の組で引く索引。全ソースから1度だけ組み、組ごとに、宣言の本体の直下の関数の署名の一覧と、本体の直下で呼んだマクロを持つ。
//! トレイトの同一性は、宣言のモジュールパス(ファイルから推定したモジュールパス + 宣言を囲む `mod 名 { … }` の並び。`module_path/enclosing_module.rs`)+ 名前である。同じクレートの `甲::変更` と `乙::変更` は別のトレイトである。
//! 引くのは、実装側がトレイトの表記から求めた見るトレイトの宣言(`implemented_trait/declaring_module.rs`)であり、宣言したモジュールが決まったものはそのモジュールの宣言だけを、決められないものは指定のクレートの同名の宣言を全部見る。
//! 見た宣言が複数あるときは、1つでも自己変更を与える関数があれば与えると答え、無くても1つでも本体の直下でマクロを呼ぶ宣言があれば完全に読めないと答える(一意に決まらない宣言と読めない宣言を違反の側へ倒す)。
//! 本体の直下のマクロの呼び出し(`body_macro_invocation.rs`)を持つのは、マクロがトレイトの既定の関数を生やせるのに、検査器がマクロを展開できず、生えた関数の署名を読めないためである。
//! 読む見出しは `trait`・`pub trait`・`pub(crate) trait`・`unsafe trait`・`pub unsafe trait` と、型引数・`where`・上位トレイトを持つものであり、前に同じ行で属性(`#[..] trait`)を書いてもよい。既定の関数の `where Self: Sized` も除外しない。
//! 上位トレイトは辿らない。`impl 下位 for 型` が成り立つには `型: 上位` が要り、それは明示の `impl 上位 for 型`(型に属する実装として別に読む)か全称の実装(対象の型を決められない実装として別に読む)でしか満たせないためである。
//! 走査範囲の外のトレイト(std と依存クレート)は索引に無い。索引に無いトレイトを検査しなくてよいかは、呼び出し側が `implemented_trait.rs` で判定する。

use std::collections::HashMap;
use std::path::PathBuf;

use super::body_macro_invocation::本体の直下のマクロの呼び出し;
use super::declaration_prefix::属性と可視性を読み飛ばす;
use super::function_signature::{本体の直下の関数の署名一覧, 自己変更を問う対象, 関数の署名};
use super::impl_header::宣言の見出しを読む;
use super::line_matching::先頭の識別子;
use super::module_path::enclosing_module::行ごとの囲むモジュールの名前一覧;
use super::module_path::モジュールパス;

/// 実装が書いたトレイトについて、索引のどの宣言を見るか。宣言したモジュールが決まったものと、決められないため同名の宣言を全部見るクレートの2つを持つ。どちらも空なら、走査範囲に宣言が無い。
pub struct 見るトレイトの宣言 {
    pub モジュール一覧: Vec<モジュールパス>,
    pub 同名の宣言を見るクレート一覧: Vec<モジュールパス>,
}

// 1つのモジュールの同じ名前のトレイトの宣言の中身。同じモジュールに同名の宣言が複数あれば、関数を1つの列へ連ねる(関数を1つも持たない宣言も空の列として持つ)。
#[derive(Default)]
struct トレイトの宣言の中身 {
    関数一覧: Vec<関数の署名>,
    本体の直下のマクロ: Option<String>, // 本体の直下で最初に呼んだマクロの名前
}

pub struct トレイトの宣言の索引 {
    宣言のモジュールと名前ごとの中身: HashMap<(モジュールパス, String), トレイトの宣言の中身>,
}

impl トレイトの宣言の索引 {
    pub fn 全ソースから組む(ソース一覧: &[(PathBuf, Vec<String>)]) -> Self {
        let mut 中身の表: HashMap<(モジュールパス, String), トレイトの宣言の中身> = HashMap::new();
        for (パス, 行一覧) in ソース一覧 {
            let ファイルのモジュール = モジュールパス::ファイルのパスから求める(パス);
            let 囲むモジュールの一覧 = 行ごとの囲むモジュールの名前一覧(行一覧);
            for (開始, 行) in 行一覧.iter().enumerate() {
                let Some(名前) = トレイトの宣言の名前(行) else {
                    continue;
                };
                let Some(見出し) = 宣言の見出しを読む(行一覧, 開始) else {
                    continue;
                };
                let 囲む名前一覧: Vec<&str> = 囲むモジュールの一覧.get(開始).into_iter().flatten().map(String::as_str).collect();
                let 本体 = 見出し.本体の文字列(行一覧);
                let 中身 = 中身の表.entry((ファイルのモジュール.下へ繋ぐ(&囲む名前一覧), 名前)).or_default();
                中身.関数一覧.extend(本体の直下の関数の署名一覧(&本体));
                中身.本体の直下のマクロ = 中身.本体の直下のマクロ.take().or_else(|| 本体の直下のマクロの呼び出し(&本体));
            }
        }
        Self {
            宣言のモジュールと名前ごとの中身: 中身の表
        }
    }

    /// そのモジュールがその名前のトレイトを宣言しているか。
    pub fn 宣言しているか(&self, モジュール: &モジュールパス, 名前: &str) -> bool {
        self.宣言のモジュールと名前ごとの中身.contains_key(&(モジュール.clone(), 名前.to_string()))
    }

    /// 見るトレイトの宣言のうち、その名前の宣言を参照し、対象へ自己変更を与える関数を宣言しているかと、宣言を完全に読めるかを答える。
    pub fn 宣言を参照する(&self, 見る: &見るトレイトの宣言, トレイトの名前: &str, 対象: &自己変更を問う対象) -> トレイトの宣言を参照した結果 {
        let 中身一覧: Vec<&トレイトの宣言の中身> = self
            .宣言のモジュールと名前ごとの中身
            .iter()
            .filter(|((モジュール, 名前), _)| 名前 == トレイトの名前 && (見る.モジュール一覧.contains(モジュール) || 見る.同名の宣言を見るクレート一覧.contains(&モジュール.クレート())))
            .map(|(_, 中身)| 中身)
            .collect();
        if 中身一覧.is_empty() {
            return トレイトの宣言を参照した結果::宣言が無い;
        }
        if let Some(関数) = 中身一覧.iter().flat_map(|中身| &中身.関数一覧).find(|関数| 対象.自己変更を与えるか(関数)) {
            return トレイトの宣言を参照した結果::自己変更を与える { 関数名: 関数.名前.clone() };
        }
        match 中身一覧.iter().find_map(|中身| 中身.本体の直下のマクロ.clone()) {
            Some(マクロ名) => トレイトの宣言を参照した結果::宣言を完全に読めない { マクロ名 },
            None => トレイトの宣言を参照した結果::自己変更を与えない,
        }
    }
}

/// トレイトの名前で走査範囲の宣言を参照した結果。
pub enum トレイトの宣言を参照した結果 {
    宣言が無い,
    自己変更を与えない,
    自己変更を与える { 関数名: String },
    宣言を完全に読めない { マクロ名: String }, // 宣言の本体の直下で呼んだマクロが生やす関数を読めない
}

// トレイトの宣言の見出しの行なら、そのトレイトの名前。同じ行の属性と可視性(`pub`・`pub(...)`)と `unsafe` を読み飛ばす。
fn トレイトの宣言の名前(行: &str) -> Option<String> {
    let mut 残り = 属性と可視性を読み飛ばす(行);
    if let Some(後ろ) = 残り.strip_prefix("unsafe").filter(|後ろ| 後ろ.starts_with(char::is_whitespace)) {
        残り = 後ろ.trim_start();
    }
    let 後ろ = 残り.strip_prefix("trait")?;
    if !後ろ.starts_with(char::is_whitespace) {
        return None;
    }
    let 名前 = 先頭の識別子(後ろ.trim_start());
    (!名前.is_empty()).then_some(名前)
}
