//! マーカーを名乗る型が実装している、走査範囲の外のトレイトを集める工程。`自己変更の検査` の3つ目の問いであり、受け取るのはマーカーを名乗る型の名前、返すのは見つけた実装の一覧である。
//! 走査範囲の外のトレイトとは、実装が書いた表記のパスの最後の要素の名前の閉包で引いても、走査範囲に宣言が1件も無いトレイトのことである(std・core・alloc と外部の依存クレートのトレイトがこれに当たる)。
//! 検査器はその宣言を読めないため、既定の関数を検査しない。検査しないことの論証は `_doc/設計/設計オントロジー.md` 2.5.3 が持ち、その論証が将来の依存の追加で腐らないように、台帳(`external_trait_ledger.rs`)が名前を固定する。
//! 設計解釈マーカー自身(`M不変データ`・`M規則` 等)は集めない。マーカーの宣言が自己変更を与える関数を持たないことを正本 `blitz_design` が定めており、その宣言は走査範囲にあるためである。
//! `derive` が生やす実装はソースの行に `impl` として現れないため、ここには集まらない。

use std::path::PathBuf;

use super::function_signature::自己変更を問う対象;
use super::identifier_boundary::識別子として現れるか;
use super::impl_header::implの見出しを読む;
use super::impl_syntax::実装の種類;
use super::line_matching::パスの最後の名前;
use super::mutable_impl_scan::自己変更の検査;
use super::syntax_patterns::オントロジートレイト;
use super::trait_declaration_index::トレイトの宣言を参照した結果;

/// マーカーを名乗る型の名前を対象の表記に含む実装が、走査範囲の外のトレイトを実装している1件。
pub struct 走査範囲の外のトレイトの実装 {
    pub マーカーの名前: String,
    pub パス: PathBuf,
    pub 行番号: usize,
    pub トレイト名: String,
}

impl 自己変更の検査<'_> {
    /// マーカーを名乗る型の名前の閉包のどれかを対象の表記に含む実装が実装している、走査範囲の外のトレイトの全部。並びはソースの並びと行の順である。
    pub fn 名前が当たった走査範囲の外のトレイト一覧(&self, マーカーの名前: &str) -> Vec<走査範囲の外のトレイトの実装> {
        let 名前の集合 = self.名前の辺一覧.閉包(マーカーの名前);
        let mut 一覧 = Vec::new();
        for (パス, 行一覧) in self.ソース一覧 {
            for 開始 in 0..行一覧.len() {
                let Some(トレイト名) = implの見出しを読む(行一覧, 開始).and_then(|見出し| self.走査範囲の外のトレイト名(&見出し, &名前の集合)) else {
                    continue;
                };
                一覧.push(走査範囲の外のトレイトの実装 {
                    マーカーの名前: マーカーの名前.to_string(),
                    パス: パス.clone(),
                    行番号: 開始 + 1,
                    トレイト名,
                });
            }
        }
        一覧
    }

    // その実装が名前の集合のどれかを対象の表記に含み、しかも走査範囲に宣言が無いトレイトの実装なら、そのトレイトの表記のパスの最後の要素の名前。
    fn 走査範囲の外のトレイト名(&self, 見出し: &super::impl_header::実装の見出し, 名前の集合: &[String]) -> Option<String> {
        let 構文 = 見出し.構文を読む()?;
        if 構文.全称の実装か() || !名前の集合.iter().any(|名前| 識別子として現れるか(構文.対象.表記(), 名前)) {
            return None;
        }
        let 実装の種類::トレイトの実装 { トレイトの表記 } = &構文.種類 else {
            return None;
        };
        let 名前 = パスの最後の名前(トレイトの表記).to_string();
        if オントロジートレイト::全部の一覧().iter().any(|マーカー| マーカー.名前() == 名前) {
            return None;
        }
        let 対象 = 自己変更を問う対象 {
            型名: &名前, 可変参照を対象にするか: false
        };
        matches!(self.トレイトの索引.宣言を参照する(&self.名前の辺一覧.閉包(&名前), &対象), トレイトの宣言を参照した結果::宣言が無い).then_some(名前)
    }
}
