//! コードだけの行の字句を順に受け取り、いまの位置がトークン木の中かを答える状態。受け取るのは語と括弧と `!` とその他の記号、返すのはトークン木の中かと、閉じた丸括弧が可視性(`pub(..)`)の括弧であったかである。
//! トークン木とは、マクロの呼び出しの引数(`名前!` の直後の `(`・`[`・`{` から対応する閉じ括弧まで)と `macro_rules! 名前` の本体のことである。トークン木の中の括弧はすべてトークン木の中である。
//! 名前と `!` の間と `!` と括弧の間には空白と改行があってもよい。`if`・`return` のように後ろへ否定の式(`!x`・`!(x)`)を置ける予約語の後ろの `!` はマクロを呼ばない。

struct 開いた括弧 {
    トークン木か: bool,
    可視性か: bool,
}

#[derive(Clone, Copy, PartialEq, Eq, Default)]
enum マクロの呼び出しの読み {
    #[default]
    無し,
    名前の後ろ,
    マクロ定義の予約語の後ろ,
    マクロ定義の名前の待ち,
    引数を開く括弧の待ち,
}

/// いまの位置を囲む括弧の並びと、次の開き括弧がマクロの引数を開くかの読み。1つのファイルを先頭の行から順に読む。
#[derive(Default)]
pub struct トークン木の入れ子 {
    開いた括弧の並び: Vec<開いた括弧>,
    読み: マクロの呼び出しの読み,
}

impl トークン木の入れ子 {
    /// いまの位置がトークン木の中か。
    pub fn 中か(&self) -> bool {
        self.開いた括弧の並び.last().is_some_and(|括弧| 括弧.トークン木か)
    }

    /// 識別子か予約語を1つ読む。
    pub fn 語を読む(&mut self, 語: &str) {
        self.読み = match self.読み {
            マクロの呼び出しの読み::マクロ定義の名前の待ち => マクロの呼び出しの読み::引数を開く括弧の待ち,
            _ if 語 == "macro_rules" => マクロの呼び出しの読み::マクロ定義の予約語の後ろ,
            _ if 否定の式を後ろに置ける予約語か(語) => マクロの呼び出しの読み::無し,
            _ => マクロの呼び出しの読み::名前の後ろ,
        };
    }

    /// `!` を1つ読む。
    pub fn 感嘆符を読む(&mut self) {
        self.読み = match self.読み {
            マクロの呼び出しの読み::名前の後ろ => マクロの呼び出しの読み::引数を開く括弧の待ち,
            マクロの呼び出しの読み::マクロ定義の予約語の後ろ => マクロの呼び出しの読み::マクロ定義の名前の待ち,
            _ => マクロの呼び出しの読み::無し,
        };
    }

    /// 開き括弧(`(`・`[`・`{`)を1つ読む。可視性かは、その括弧が `pub` の直後の `(` であるかである。
    pub fn 開き括弧を読む(&mut self, 可視性か: bool) {
        let トークン木か = self.中か() || self.読み == マクロの呼び出しの読み::引数を開く括弧の待ち;
        self.開いた括弧の並び.push(開いた括弧 { トークン木か, 可視性か });
        self.読み = マクロの呼び出しの読み::無し;
    }

    /// 閉じ括弧(`)`・`]`・`}`)を1つ読み、閉じた括弧が可視性の丸括弧であったかを返す。
    pub fn 閉じ括弧を読む(&mut self) -> bool {
        self.読み = マクロの呼び出しの読み::無し;
        self.開いた括弧の並び.pop().is_some_and(|括弧| 括弧.可視性か)
    }

    /// 括弧と `!` 以外の記号を1つ読む。
    pub fn その他の記号を読む(&mut self) {
        self.読み = マクロの呼び出しの読み::無し;
    }
}

// 後ろへ否定の式を置ける予約語か。この語の後ろの `!` はマクロを呼ばない。
fn 否定の式を後ろに置ける予約語か(語: &str) -> bool {
    matches!(語, "if" | "while" | "match" | "return" | "break" | "in" | "yield" | "else" | "move" | "impl" | "as" | "let" | "mut" | "for" | "where" | "dyn")
}

#[cfg(test)]
mod tests {
    use super::トークン木の入れ子;

    fn 読む(入れ子: &mut トークン木の入れ子, 字句一覧: &[&str]) {
        for 字句 in 字句一覧 {
            match *字句 {
                "!" => 入れ子.感嘆符を読む(),
                "(" | "[" | "{" => 入れ子.開き括弧を読む(false),
                ")" | "]" | "}" => {
                    入れ子.閉じ括弧を読む();
                }
                "=" | ";" | "#" => 入れ子.その他の記号を読む(),
                語 => 入れ子.語を読む(語),
            }
        }
    }

    #[test]
    fn マクロの引数とmacro_rulesの本体の中だけをトークン木と答える() {
        for (字句一覧, 期待) in [
            (&["通す", "!", "("][..], true),
            (&["通す", "!", "[", "{"][..], true),
            (&["macro_rules", "!", "生やす", "{"][..], true),
            (&["通す", "!", "(", ")", "{"][..], false),
            (&["if", "!", "("][..], false),
            (&["甲", "!", "=", "("][..], false),
            (&["#", "!", "["][..], false),
        ] {
            let mut 入れ子 = トークン木の入れ子::default();
            読む(&mut 入れ子, 字句一覧);
            assert_eq!(入れ子.中か(), 期待, "{字句一覧:?}");
        }
    }
}
