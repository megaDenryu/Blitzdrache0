//! 共有の指し先の検査と、2つの基底の契約の排他の試験。`M不変データ` の型が `M共有される不変データ` を名乗る型を `Arc` で持つことだけが許され、
//! 共有を名乗らない型を指す `Arc`・共有を名乗る型を借りる `&`・`Rc` は違反になることと、`M共有される不変データ` を名乗る型自身に純粋データ規約が当たることと、
//! 同じ型が2つの基底の契約を同時に名乗ると違反になることを固定する。

use super::tests::{ソース, 全部の説明関数を連ねた違反の説明一覧};

const 共有される地図: &str = "pub struct 地図 {\n    つながり: Vec<u8>,\n}\nimpl M共有される不変データ for 地図 {}\n";

// 地図を1つのフィールドで持つ規則の定義。`型の表記` がフィールドの型である。
fn 地図を持つ規則(型の表記: &str) -> String {
    format!("{共有される地図}#[derive(Clone)]\npub struct 規則 {{\n    地図: {型の表記},\n}}\nimpl M不変データ for 規則 {{}}\nimpl M規則 for 規則 {{}}\n")
}

#[test]
fn 構文解析_共有される不変データを指すarcは修飾の有無に依らず違反にならない() {
    for 型の表記 in ["Arc<地図>", "std::sync::Arc<地図>"] {
        let 説明一覧 = 全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", &地図を持つ規則(型の表記))]);
        assert!(説明一覧.is_empty(), "{型の表記}: {説明一覧:?}");
    }
}

#[test]
fn 構文解析_共有される不変データを名乗らない型を指すarcは違反になる() {
    let 内容 = format!("{}pub struct 名簿 {{\n    人数: u8,\n}}\n", 地図を持つ規則("Arc<名簿>"));
    let 説明一覧 = 全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", &内容)]);
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains("M規則 `規則` の定義の `Arc<名簿>` の中身 `名簿` が `M共有される不変データ` を名乗っていない"));
}

#[test]
fn 構文解析_共有される不変データを借りる参照とrcは違反になる() {
    let 借りる = 全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", &地図を持つ規則("&地図"))]);
    assert_eq!(借りる.len(), 1, "{借りる:?}");
    assert!(借りる[0].contains("の定義は参照(&)を持てません"));
    let 数える = 全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", &地図を持つ規則("Rc<地図>"))]);
    assert_eq!(数える.len(), 1, "{数える:?}");
    assert!(数える[0].contains("の定義は共有の指し先 `Rc` を持てません"));
}

#[test]
fn 構文解析_中身を1つの名前として読めないarcは違反になる() {
    let 説明一覧 = 全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", &地図を持つ規則("Arc<Vec<地図>>"))]);
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains("の中身を1つの名前として読めない"));
}

#[test]
fn 構文解析_共有される不変データを名乗る型自身も内部可変性を持てない() {
    let 内容 = "pub struct 地図 {\n    数: RefCell<u8>,\n}\nimpl M共有される不変データ for 地図 {}\n";
    let 説明一覧 = 全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", 内容)]);
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains("M共有される不変データ `地図` の定義は内部可変性 `RefCell` を持てません"));
}

#[test]
fn 構文解析_不変データと共有される不変データを同時に名乗る型は違反になる() {
    let 内容 = format!("{共有される地図}impl M不変データ for 地図 {{}}\n");
    let 説明一覧 = 全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", &内容)]);
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains("M共有される不変データ `地図` は `M不変データ` も名乗っている"));
}
