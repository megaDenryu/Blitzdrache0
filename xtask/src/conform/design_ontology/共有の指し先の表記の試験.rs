//! 共有の指し先の表記の読み取りの試験。標準の表記の `Arc` の中身の型の表記を読むことと、標準でない修飾の `Arc` を修飾まで含めた表記で返すことと、
//! `Rc`・`Weak` を別の指し先として読み、型引数を取らない現れと識別子の一部を読まないことを固定する。

use super::共有の指し先の表記::{共有の指し先, 行の共有の指し先一覧};

#[test]
fn 標準の表記のarcは修飾の有無に依らず中身の型の表記を読む() {
    for 行 in [
        "地図: Arc<地点と経路のグラフ>,",
        "地図: std::sync::Arc<地点と経路のグラフ>,",
        "地図: alloc::sync::Arc< 地点と経路のグラフ >,",
        "地図: std :: sync :: Arc<地点と経路のグラフ>,",
    ] {
        assert_eq!(
            行の共有の指し先一覧(行),
            vec![共有の指し先::Arc {
                中身の型の表記: "地点と経路のグラフ".to_string()
            }],
            "{行}"
        );
    }
    assert_eq!(
        行の共有の指し先一覧("地図: Arc<Vec<地図>>,"),
        vec![共有の指し先::Arc {
            中身の型の表記: "Vec<地図>".to_string()
        }]
    );
}

#[test]
fn 標準でない修飾のarcは修飾まで含めた書かれた文字列で返す() {
    for (行, 書かれた文字列) in [
        ("地図: 別の::Arc<地図>,", "別の::Arc"),
        ("地図: sync::Arc<地図>,", "sync::Arc"),
        ("地図: ::std::sync::Arc<地図>,", "::std::sync::Arc"),
        ("地図: <甲 as 乙>::Arc<地図>,", "::Arc"),
    ] {
        assert_eq!(
            行の共有の指し先一覧(行),
            vec![共有の指し先::標準でない修飾のArc {
                書かれた文字列: 書かれた文字列.to_string()
            }],
            "{行}"
        );
    }
}

#[test]
fn rcとweakは参照を数える別の指し先として読み型引数を取らない現れと識別子の一部は読まない() {
    assert_eq!(
        行の共有の指し先一覧("甲: Rc<地図>, 乙: Weak<地図>,"),
        vec![共有の指し先::参照を数える別の指し先 { 名前: "Rc" }, 共有の指し先::参照を数える別の指し先 { 名前: "Weak" }]
    );
    assert!(行の共有の指し先一覧("let 地図 = Arc::new(地図); Arcの設定: u8, 甲Rc: u8").is_empty());
}
