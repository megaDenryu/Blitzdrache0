//! 名前が当たった別の型の実装の台帳のうち、陳腐化の試験。台帳に載っているのに自己変更を与える実装として見つからなくなった行を違反にすることを固定する。
//! 一覧に無い区分を名乗る行を違反にすることと、型を包む実装の区分で行を除けることも、このファイルが固定する。
//! 台帳の行が別の型の実装を除くことは、同じクレートの別のモジュールの形をこのファイルが持ち、ほかの形は `definition_position_tests.rs`(同じファイルの別の `mod`)・`impl_target_tests.rs`(別のモジュールを指すパス)・`../type_identity_tests.rs`(別のクレート)が固定する。

use super::super::name_match_exclusion_ledger::{台帳の行, 名前が当たった別の型の実装の台帳};
use super::super::tests::{ソース, 台帳を与えた自己変更の違反の説明一覧};

fn 別の型の実装を除く台帳() -> 名前が当たった別の型の実装の台帳 {
    名前が当たった別の型の実装の台帳::行一覧から組む(vec![台帳の行 {
        マーカーの名前: "規則",
        パス: "crates/a/src/b.rs",
        見出し: "impl crate::c::規則",
        区分: "同じ名前の別の型",
        除外する理由: "この実装の対象は crate::c の別の型であり、マーカーを名乗る crate::a の型ではない",
    }])
}

#[test]
fn 該当しなくなった台帳の行は陳腐化として違反になる() {
    let ソース一覧 = vec![ソース("crates/a/src/a.rs", "pub struct 規則;\nimpl M不変データ for 規則 {}\n")];
    let 説明一覧 = 台帳を与えた自己変更の違反の説明一覧(ソース一覧, &別の型の実装を除く台帳());
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains("名前が当たった別の型の実装の台帳に載っている `impl crate::c::規則`"), "{説明一覧:?}");
}

#[test]
fn 構文解析_同じクレートの別モジュールの同名の型の実装も名前で検査され台帳の行で除ける() {
    let ソース一覧 = || {
        vec![
            ソース(
                "crates/a/src/x.rs",
                "pub struct 規則;
impl M不変データ for 規則 {}
impl M規則 for 規則 {}
",
            ),
            ソース(
                "crates/a/src/y.rs",
                "pub struct 規則;
impl 規則 {
    pub fn 変える(&mut self) {}
}
",
            ),
        ]
    };
    let 空の台帳 = 名前が当たった別の型の実装の台帳::行一覧から組む(Vec::new());
    let 説明一覧 = 台帳を与えた自己変更の違反の説明一覧(ソース一覧(), &空の台帳);
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains("M不変データ `規則` は自分の型への可変参照を受け手か引数に持つ関数を持てません"), "{説明一覧:?}");
    let 台帳 = 名前が当たった別の型の実装の台帳::行一覧から組む(vec![台帳の行 {
        マーカーの名前: "規則",
        パス: "crates/a/src/y.rs",
        見出し: "impl 規則",
        区分: "同じ名前の別の型",
        除外する理由: "この実装の対象は同じクレートの別のモジュールの型であり、マーカーを名乗る x の型ではない",
    }]);
    assert!(台帳を与えた自己変更の違反の説明一覧(ソース一覧(), &台帳).is_empty());
}

#[test]
fn 一覧に無い区分を名乗る台帳の行は違反になる() {
    let 台帳 = 名前が当たった別の型の実装の台帳::行一覧から組む(vec![台帳の行 {
        マーカーの名前: "規則",
        パス: "crates/a/src/b.rs",
        見出し: "impl crate::c::規則",
        区分: "なんとなく",
        除外する理由: "区分を名乗り損ねた行",
    }]);
    let ソース一覧 = vec![ソース(
        "crates/a/src/a.rs",
        "pub struct 規則;
impl M不変データ for 規則 {}
",
    )];
    let 説明一覧 = 台帳を与えた自己変更の違反の説明一覧(ソース一覧, &台帳);
    assert_eq!(説明一覧.len(), 2, "{説明一覧:?}");
    assert!(説明一覧.iter().any(|説明| 説明.contains("が名乗る区分 `なんとなく` は、除いてよい区分の一覧に無い")), "{説明一覧:?}");
}

#[test]
fn 型を包む実装は別の型ではないため型を包む実装の区分で除ける() {
    let ソース一覧 = || {
        vec![ソース(
            "crates/a/src/x.rs",
            "pub struct 規則;
impl M不変データ for 規則 {}
pub trait 詰める {
    fn 詰める(&mut self);
}
impl 詰める for Vec<規則> {
    fn 詰める(&mut self) {}
}
",
        )]
    };
    let 空の台帳 = 名前が当たった別の型の実装の台帳::行一覧から組む(Vec::new());
    assert_eq!(台帳を与えた自己変更の違反の説明一覧(ソース一覧(), &空の台帳).len(), 1);
    let 台帳 = 名前が当たった別の型の実装の台帳::行一覧から組む(vec![台帳の行 {
        マーカーの名前: "規則",
        パス: "crates/a/src/x.rs",
        見出し: "impl 詰める for Vec<規則>",
        区分: "型を包む実装",
        除外する理由: "この実装の対象は規則を包む Vec であり、可変の受け手 `&mut Vec<規則>` は包んだ規則の値を書き換えない",
    }]);
    assert!(台帳を与えた自己変更の違反の説明一覧(ソース一覧(), &台帳).is_empty());
}
