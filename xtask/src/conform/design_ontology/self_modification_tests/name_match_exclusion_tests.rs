//! 名前が当たった別の型の実装の台帳の試験。名前で実装を集めるのは過大近似であるため、同じ名前の別の型の実装がこの検査に当たる。
//! 台帳に理由を書いた行があるものだけを除き、台帳に載っているのに当たらなくなった行は陳腐化として違反にすることを固定する。

use super::super::name_match_exclusion_ledger::{台帳の行, 名前が当たった別の型の実装の台帳};
use super::super::tests::{ソース, 台帳を与えた自己変更の違反の説明一覧};

const 自己変更の違反: &str = "M不変データ `規則` は自分の型への可変参照を受け手か引数に持つ関数を持てません";

// 別のモジュールで定義した同名の型の、可変の関数を持つ実装。
fn 別の型の実装のソース一覧() -> Vec<(std::path::PathBuf, Vec<String>)> {
    vec![
        ソース("crates/a/src/a.rs", "pub struct 規則;\nimpl M不変データ for 規則 {}\n"),
        ソース("crates/a/src/c.rs", "pub struct 規則;\n"),
        ソース("crates/a/src/b.rs", "impl crate::c::規則 {\n    fn 変える(&mut self) {}\n}\n"),
    ]
}

fn 別の型の実装を除く台帳() -> 名前が当たった別の型の実装の台帳 {
    名前が当たった別の型の実装の台帳::行一覧から組む(vec![台帳の行 {
        マーカーの名前: "規則",
        パス: "crates/a/src/b.rs",
        見出し: "impl crate::c::規則",
        除外する理由: "この実装の対象は crate::c の別の型であり、マーカーを名乗る crate::a の型ではない",
    }])
}

#[test]
fn 同じ名前の別の型の実装は台帳が空なら違反になる() {
    let 説明一覧 = 台帳を与えた自己変更の違反の説明一覧(別の型の実装のソース一覧(), &名前が当たった別の型の実装の台帳::行一覧から組む(Vec::new()));
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains(自己変更の違反), "{説明一覧:?}");
}

#[test]
fn 台帳の行が当たれば違反にならない() {
    let 説明一覧 = 台帳を与えた自己変更の違反の説明一覧(別の型の実装のソース一覧(), &別の型の実装を除く台帳());
    assert!(説明一覧.is_empty(), "{説明一覧:?}");
}

#[test]
fn 該当しなくなった台帳の行は陳腐化として違反になる() {
    let ソース一覧 = vec![ソース("crates/a/src/a.rs", "pub struct 規則;\nimpl M不変データ for 規則 {}\n")];
    let 説明一覧 = 台帳を与えた自己変更の違反の説明一覧(ソース一覧, &別の型の実装を除く台帳());
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains("名前が当たった別の型の実装の台帳に載っている `impl crate::c::規則`"), "{説明一覧:?}");
}
