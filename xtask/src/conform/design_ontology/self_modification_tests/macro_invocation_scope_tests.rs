//! 自己変更の禁止の試験のうち、モジュールの直下で波括弧を使って呼んだマクロの本体(マクロの呼び出しの中)に書いた `trait`・`use`・`mod` を、モジュールの宣言と取り込みとして索引せず、
//! それらが隠しうる名前を書いた実装を黙って通さないことを確かめるもの。マクロは中身をモジュールの項目として展開しうるが、検査器は展開した後の項目を知らないため、
//! prelude の名前・走査範囲の外のクレートの名前・別の型として通す前に、マクロの呼び出しの中の名前が隠しうるかを問わなければならない。どの試験もソースの並び順を入れ替えて同じ結果になることを確かめる。

use std::path::PathBuf;

use super::super::tests::{ソース, 全部の説明関数を連ねた違反の説明一覧};

const 定義: &str = "pub struct 規則;\nimpl M不変データ for 規則 {}\n";
const 隠しうるトレイトの違反: &str = "同じモジュールで波括弧を使って呼んだマクロの本体の use か項目が隠しうるトレイト";

fn 違反の説明一覧(ソース一覧: &[(&str, &str)]) -> Vec<String> {
    全部の説明関数を連ねた違反の説明一覧(ソース一覧.iter().map(|(パス, 内容)| ソース(パス, 内容)).collect::<Vec<(PathBuf, Vec<String>)>>())
}

fn 違反が1件だけあり説明が含む(ソース一覧: &[(&str, &str)], 含む語: &str) {
    let 説明一覧 = 違反の説明一覧(ソース一覧);
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains(含む語), "{説明一覧:?}");
}

// 2つの断片を両方の並び順で繋いだもの。
fn 両方の並び(前: &str, 後: &str) -> [String; 2] {
    [format!("{前}{後}"), format!("{後}{前}")]
}

#[test]
fn マクロの呼び出しの中で宣言したpreludeの名前のトレイトの実装は黙って通らない() {
    for 並び in 両方の並び("素通し! {\n    pub trait Clone {\n        fn 変える(&mut self);\n    }\n}\n", "impl Clone for 規則 {}\n") {
        違反が1件だけあり説明が含む(&[("crates/a/src/x.rs", &format!("{定義}{並び}"))], &format!("{隠しうるトレイトの違反} `Clone`"));
    }
}

#[test]
fn マクロの呼び出しの中で宣言したトレイトは走査範囲の外のglobの名前として通らない() {
    for 並び in 両方の並び("素通し! {\n    trait 変更 {\n        fn 読む(&self) {}\n    }\n}\n", "use std::fmt::*;\n") {
        違反が1件だけあり説明が含む(&[("crates/a/src/x.rs", &format!("{定義}{並び}impl 変更 for 規則 {{}}\n"))], &format!("{隠しうるトレイトの違反} `変更`"));
    }
}

#[test]
fn マクロの呼び出しの中のモジュールを起点に書いた修飾のあるトレイトは黙って通らない() {
    let マクロ = "素通し! {\n    mod 内 {\n        pub trait 変更 {}\n    }\n}\n";
    違反が1件だけあり説明が含む(&[("crates/a/src/x.rs", &format!("{定義}{マクロ}impl 内::変更 for 規則 {{}}\n"))], &format!("{隠しうるトレイトの違反} `内::変更`"));
}

#[test]
fn マクロの呼び出しの中のuseの別名で名指した型の実装は結び付けられない実装になる() {
    for 並び in 両方の並び("素通し! {\n    use crate::x::規則 as 別名;\n}\n", "impl 別名 {\n    fn 変える(&mut self) {}\n}\n") {
        違反が1件だけあり説明が含む(&[("crates/a/src/x.rs", 定義), ("crates/a/src/y.rs", &並び)], "同じモジュールで波括弧を使って呼んだマクロの本体の use か項目が隠しうる");
    }
}

#[test]
fn 名前を持ち込まないマクロの呼び出しはpreludeの名前のトレイトの実装を妨げない() {
    for 並び in 両方の並び("三成分の量を定義する! {\n    速度, メートル毎秒\n}\n", "impl Clone for 規則 {}\n") {
        assert!(違反の説明一覧(&[("crates/a/src/x.rs", &format!("{定義}{並び}"))]).is_empty());
    }
}
