//! 自己変更の禁止の試験のうち、トレイトの宣言の本体の直下のマクロの呼び出しを確かめるもの。宣言の本体の直下の関数だけを読む形は、
//! `trait 変更可能 { 自己変更を生やす!(); }` のようにマクロが生やす既定の関数 `fn 変える(&mut self)` を読めず、`M不変データ` の型によるその実装を通していた。

use super::super::tests::{ソース, 全部の説明関数を連ねた違反の説明一覧};

const 読めないトレイトの違反: &str = "のトレイトの実装は、宣言の本体の直下でマクロ";
const 定義: &str = "pub struct 規則;\nimpl M不変データ for 規則 {}\n";

fn 説明一覧(内容: &str) -> Vec<String> {
    全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", 内容)])
}

#[test]
fn 既定の関数を生やすマクロを宣言の本体で呼ぶトレイトの実装は違反になる() {
    let 説明一覧 = 説明一覧(&format!(
        "macro_rules! 自己変更を生やす {{\n    () => {{\n        fn 変える(&mut self) {{}}\n    }};\n}}\ntrait 変更可能 {{\n    自己変更を生やす!();\n}}\n{定義}impl 変更可能 for 規則 {{}}\n"
    ));
    assert_eq!(説明一覧.len(), 2, "{説明一覧:?}");
    assert!(
        説明一覧.iter().any(|説明| 説明.contains("M不変データ `規則` の") && 説明.contains(読めないトレイトの違反) && 説明.contains("`自己変更を生やす!`")),
        "{説明一覧:?}"
    );
    assert!(説明一覧.iter().any(|説明| 説明.contains("macro_rules! 自己変更を生やす の fn 変える")), "{説明一覧:?}");
}

#[test]
fn 項目を生やしうるどのマクロを宣言の本体で呼ぶトレイトの実装も違反になる() {
    for (呼び出し, マクロ名) in [("include!(\"methods.rs\");", "`include!`"), ("crate::生やす!();", "`crate::生やす!`"), ("生やす! {}", "`生やす!`")] {
        let 説明一覧 = 説明一覧(&format!("trait 変更可能 {{\n    {呼び出し}\n}}\n{定義}impl 変更可能 for 規則 {{}}\n"));
        assert_eq!(説明一覧.len(), 1, "{呼び出し}: {説明一覧:?}");
        assert!(説明一覧[0].contains(読めないトレイトの違反) && 説明一覧[0].contains(マクロ名), "{説明一覧:?}");
    }
}

#[test]
fn マクロを本体の直下で呼ばないトレイトと不変データでない型の実装は違反にならない() {
    let 関数の本体の中のマクロ = format!("trait 読める {{\n    fn 読む(&self) {{\n        println!(\"読む\");\n    }}\n}}\n{定義}impl 読める for 規則 {{}}\n");
    assert!(説明一覧(&関数の本体の中のマクロ).is_empty(), "{:?}", 説明一覧(&関数の本体の中のマクロ));
    let 不変データでない型 = "trait 変更可能 {\n    include!(\"methods.rs\");\n}\npub struct 他;\nimpl 変更可能 for 他 {}\n";
    assert!(説明一覧(不変データでない型).is_empty(), "{:?}", 説明一覧(不変データでない型));
}
