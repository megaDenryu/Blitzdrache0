//! 自己変更の禁止の試験のうち、名前の閉包と、実装の在り処を問わないことを確かめるもの。
//! 検査器は、`M不変データ` を名乗る型の名前から `type 別名 = 右辺;` と `use …::元 as 別名;` の辺を双方向にたどり、閉じた名前のどれかが実装の対象の表記に識別子の境界で現れれば、その実装を検査する。
//! 名前解決をやめたため、実装が関数の本体の中にあっても、波括弧付きのモジュールの中にあっても、マクロの本体の中にあっても、`#[cfg(..)]` が付いていても同じく検査する。
//! 名前の当たり方は識別子の境界で見る。`歩数を動かす領域` のような区切りの無い日本語の識別子の途中では当たらない。

use super::super::tests::{ソース, 全部の説明関数を連ねた違反の説明一覧};

const 自己変更の違反: &str = "M不変データ `規則` は自分の型への可変参照を受け手か引数に持つ関数を持てません";
const 定義: &str = "pub struct 規則;\nimpl M不変データ for 規則 {}\n";

fn 違反が1件だけあり自己変更の違反である(内容: &str) {
    let 説明一覧 = 全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", 内容)]);
    assert_eq!(説明一覧.len(), 1, "{内容}: {説明一覧:?}");
    assert!(説明一覧[0].contains(自己変更の違反), "{説明一覧:?}");
}

#[test]
fn 型の別名を対象に書いた実装は違反になる() {
    違反が1件だけあり自己変更の違反である(&format!("{定義}type 別名 = 規則;\nimpl 別名 {{\n    fn 変える(&mut self) {{}}\n}}\n"));
}

#[test]
fn 別名の側へマーカーを書いても本体の型名の実装は違反になる() {
    let 内容 = "pub struct 規則;\ntype 別名 = 規則;\nimpl M不変データ for 別名 {}\nimpl 規則 {\n    fn 変える(&mut self) {}\n}\n";
    let 説明一覧 = 全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", 内容)]);
    assert!(説明一覧.iter().any(|説明| 説明.contains("は自分の型への可変参照を受け手か引数に持つ関数を持てません")), "{説明一覧:?}");
}

#[test]
fn 別名で取り込んだ名前を対象に書いた実装は違反になる() {
    違反が1件だけあり自己変更の違反である(&format!("{定義}use crate::x::規則 as 別名;\nimpl 別名 {{\n    fn 変える(&mut self) {{}}\n}}\n"));
}

#[test]
fn 実装の在り処を問わず検査する() {
    for 在り処 in [
        "fn 局所処理() {\n    impl 規則 {\n        fn 変える(&mut self) {}\n    }\n}\n",
        "mod 内 {\n    impl super::規則 {\n        fn 変える(&mut self) {}\n    }\n}\n",
        "#[cfg(test)]\nimpl 規則 {\n    fn 変える(&mut self) {}\n}\n",
    ] {
        違反が1件だけあり自己変更の違反である(&format!("{定義}{在り処}"));
    }
}

#[test]
fn 区切りの無い日本語の識別子の途中では名前が当たらない() {
    let 内容 = format!("{定義}pub struct 規則の台帳;\nimpl 規則の台帳 {{\n    fn 変える(&mut self) {{}}\n}}\n");
    let 説明一覧 = 全部の説明関数を連ねた違反の説明一覧(vec![ソース("crates/a/src/x.rs", &内容)]);
    assert!(説明一覧.is_empty(), "{説明一覧:?}");
}
