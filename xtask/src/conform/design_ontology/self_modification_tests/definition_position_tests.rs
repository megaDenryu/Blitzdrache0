//! 自己変更の禁止と純粋データ規約の試験のうち、型の同一性の片方である定義のモジュールを、ファイルの単位でなく定義の行の位置のモジュール(囲む `mod 名 { … }` の並び)で数えることを確かめるもの。
//! 波括弧付きのモジュールの中で定義した `M不変データ` の型を、そのモジュールを名指す修飾か `use` を書いた実装へ結び付けることと、
//! `impl M不変データ for 型` の定義を、実装の位置のモジュールの直下の定義から採り、関数の本体の中の局所の定義と別の波括弧付きのモジュールの定義を採らないことを固定する。
//! 自己変更の禁止の検査は名前で実装を集めるため、同じ名前の別のモジュールの型の実装も当たる。それを台帳で除くことは `name_match_exclusion_tests.rs` が固定する。

use std::path::PathBuf;

use super::super::name_match_exclusion_ledger::{台帳の行, 名前が当たった別の型の実装の台帳};
use super::super::tests::{ソース, 全部の説明関数を連ねた違反の説明一覧, 台帳を与えた自己変更の違反の説明一覧};

const 型の自己変更の違反: &str = "M不変データ `規則` は自分の型への可変参照を受け手か引数に持つ関数を持てません";
const 内部可変性の違反: &str = "M不変データ `規則` の定義は内部可変性 `Cell` を持てません";
const 可変の関数を持つ固有の実装: &str = "impl 規則 {\n    fn 変える(&mut self) {}\n}\n";
const 内部可変性を持つ定義: &str = "pub struct 規則 {\n    値: std::cell::Cell<u8>,\n}\n";

fn 違反の説明一覧(ソース一覧: &[(&str, &str)]) -> Vec<String> {
    全部の説明関数を連ねた違反の説明一覧(ソース一覧.iter().map(|(パス, 内容)| ソース(パス, 内容)).collect::<Vec<(PathBuf, Vec<String>)>>())
}

fn 説明を含む違反が1件だけある(説明一覧: &[String], 含む語: &str) {
    assert_eq!(説明一覧.iter().filter(|説明| 説明.contains(含む語)).count(), 1, "{説明一覧:?}");
}

// 2つの断片を両方の並び順で繋いだもの。
fn 両方の並び(前: &str, 後: &str) -> [String; 2] {
    [format!("{前}{後}"), format!("{後}{前}")]
}

#[test]
fn 波括弧付きのモジュールの中で定義したm不変データの型は別のファイルの修飾の無い実装へ結び付く() {
    let 定義 = "pub mod 内 {\n    pub struct 規則;\n    impl M不変データ for 規則 {}\n}\n";
    let 実装 = format!("use crate::x::内::規則;\n{可変の関数を持つ固有の実装}");
    説明を含む違反が1件だけある(&違反の説明一覧(&[("crates/a/src/x.rs", 定義), ("crates/a/src/y.rs", &実装)]), 型の自己変更の違反);
}

#[test]
fn 波括弧付きのモジュールの中で定義したm不変データの型は同じファイルの入れ子のモジュールの修飾のある実装へ結び付く() {
    let 定義と実装 = "pub mod 内 {\n    pub struct 規則;\n    impl M不変データ for 規則 {}\n    mod tests {\n        mod 深い {\n            impl super::super::規則 {\n                fn 変える(&mut self) {}\n            }\n        }\n    }\n}\n";
    説明を含む違反が1件だけある(&違反の説明一覧(&[("crates/a/src/x.rs", 定義と実装)]), 型の自己変更の違反);
}

#[test]
fn 局所の同名の構造体はm不変データの定義として採らず取り込んだ型の定義を検査する() {
    for 並び in 両方の並び("fn 局所処理() {\n    struct 規則;\n}\n", "use crate::x::規則;\n") {
        let 説明一覧 = 違反の説明一覧(&[
            ("crates/a/src/x.rs", &format!("{内部可変性を持つ定義}{可変の関数を持つ固有の実装}")),
            ("crates/a/src/y.rs", &format!("{並び}impl M不変データ for 規則 {{}}\n")),
        ]);
        assert_eq!(説明一覧.len(), 2, "{説明一覧:?}");
        説明を含む違反が1件だけある(&説明一覧, 内部可変性の違反);
        説明を含む違反が1件だけある(&説明一覧, 型の自己変更の違反);
    }
}

#[test]
fn 別の波括弧付きのモジュールの同名の構造体はm不変データの定義として採らず取り込んだ型の定義を検査する() {
    for 並び in 両方の並び("mod 内 {\n    pub struct 規則;\n}\n", "use crate::x::規則;\n") {
        let 説明一覧 = 違反の説明一覧(&[
            ("crates/a/src/x.rs", &format!("{内部可変性を持つ定義}{可変の関数を持つ固有の実装}")),
            ("crates/a/src/y.rs", &format!("{並び}impl M不変データ for 規則 {{}}\n")),
        ]);
        assert_eq!(説明一覧.len(), 2, "{説明一覧:?}");
        説明を含む違反が1件だけある(&説明一覧, 内部可変性の違反);
        説明を含む違反が1件だけある(&説明一覧, 型の自己変更の違反);
    }
}

#[test]
fn 局所か別のモジュールの定義しか無く取り込みも無いm不変データの型は一意に決まらない() {
    for 定義 in ["fn 局所処理() {\n    struct 規則;\n}\n", "mod 内 {\n    pub struct 規則;\n}\n"] {
        let 説明一覧 = 違反の説明一覧(&[("crates/a/src/y.rs", &format!("{定義}impl M不変データ for 規則 {{}}\n"))]);
        assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
        説明を含む違反が1件だけある(&説明一覧, "M不変データ `規則` の同名の定義が複数あり一意に決まらない");
    }
}

#[test]
fn 同じファイルの別のモジュールの同名の型の実装も名前で検査され台帳の行で除ける() {
    let 内容 = format!(
        "pub mod 内 {{
    pub struct 規則;
    impl M不変データ for 規則 {{}}
}}
pub struct 規則;
{可変の関数を持つ固有の実装}"
    );
    let ソース一覧 = || vec![ソース("crates/a/src/x.rs", &内容)];
    let 空の台帳 = 名前が当たった別の型の実装の台帳::行一覧から組む(Vec::new());
    let 説明一覧 = 台帳を与えた自己変更の違反の説明一覧(ソース一覧(), &空の台帳);
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains(型の自己変更の違反), "{説明一覧:?}");
    let 台帳 = 名前が当たった別の型の実装の台帳::行一覧から組む(vec![台帳の行 {
        マーカーの名前: "規則",
        パス: "crates/a/src/x.rs",
        見出し: "impl 規則",
        区分: "同じ名前の別の型",
        除外する理由: "この実装の対象はファイルの直下の別の型であり、マーカーを名乗る `内` の中の型ではない",
    }]);
    assert!(台帳を与えた自己変更の違反の説明一覧(ソース一覧(), &台帳).is_empty());
}
