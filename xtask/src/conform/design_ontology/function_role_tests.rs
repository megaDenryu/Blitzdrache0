//! 関数役割の宣言(`const _: M遷移関数<...> = ...`)が確認関数を通ることの検査の試験。

use super::syntax_checker::クレート構文検査;
use super::tests::{ソース, 全部の説明関数を連ねた違反の説明一覧};

#[test]
fn 関数役割_確認関数を通る宣言は違反にならない() {
    let ソース一覧 = vec![ソース(
        "crates/a/src/x.rs",
        "const _: M射影関数<位置, 描画位置> = 射影関数として確認する(位置::射影する);\nconst _: M解釈関数<入力, 意図> = blitz_design::解釈関数として確認する(入力::解釈する);\nconst _: M遷移関数<位置, 意図, 規則, 出来事> =\n    crate::ontology::遷移関数として確認する(位置::遷移する);\n",
    )];
    assert!(全部の説明関数を連ねた違反の説明一覧(ソース一覧).is_empty());
}

#[test]
fn 関数役割_確認関数を通らない宣言は行番号付きで違反になる() {
    let ソース一覧 = vec![ソース(
        "crates/a/src/x.rs",
        "pub struct 位置;\nconst _: M射影関数<位置, 描画位置> = 位置::射影する;\nconst _: M遷移関数<位置, 意図, 規則, 出来事> = 解釈関数として確認する(位置::遷移する);\n",
    )];
    let 違反一覧 = クレート構文検査::生成する(ソース一覧).すべての関数役割の宣言が確認関数を通ること().違反一覧();
    let 説明一覧: Vec<String> = 違反一覧.iter().map(|違反| format!("{違反}")).collect();
    assert_eq!(説明一覧.len(), 2);
    assert!(説明一覧[0].ends_with("x.rs:2: 設計オントロジー: `M射影関数` の宣言の右辺は `射影関数として確認する(` で始まらなければなりません"));
    assert!(説明一覧[1].ends_with("x.rs:3: 設計オントロジー: `M遷移関数` の宣言の右辺は `遷移関数として確認する(` で始まらなければなりません"));
}
