//! 型の定義の探索が、再公開(`pub use`)をたどって定義へ行き着くことと、起点の予約語の無い相対の `use`(`use 子::型;`)を子のモジュールからの相対として読むことの試験。
//! どちらも、定義が見つかったことを、たどった先の定義にだけ在る内部可変性の違反が出ることで確かめる。たどれなければ「定義が見つかりません」の違反になる。

use super::tests::{ソース, 全部の説明関数を連ねた違反の説明一覧};

const 内部可変性を持つ定義: &str = "pub struct 位置 {\n    東: std::cell::Cell<f32>,\n}\n";

fn 内部可変性の違反だけが出る(ソース一覧: Vec<(std::path::PathBuf, Vec<String>)>) {
    let 説明一覧 = 全部の説明関数を連ねた違反の説明一覧(ソース一覧);
    assert_eq!(説明一覧.len(), 1, "{説明一覧:?}");
    assert!(説明一覧[0].contains("M不変データ `位置` の定義は内部可変性 `Cell` を持てません"), "{説明一覧:?}");
}

/// 反証: 取り込み元(クレートの根)の直下だけを見ると、定義が見つからず、節点のモジュールパスが空になって偽の反例を出す。
#[test]
fn 再公開した親のモジュールから取り込んだ型は再公開をたどって定義を採る() {
    let 根 = ソース("crates/a/src/lib.rs", "mod 内;\npub use 内::位置;\n");
    let 内 = ソース("crates/a/src/内.rs", 内部可変性を持つ定義);
    let 実装 = ソース("crates/a/src/使う.rs", "use crate::位置;\nimpl M不変データ for 位置 {}\n");
    内部可変性の違反だけが出る(vec![根, 内, 実装]);
}

/// 反証: 再公開を2段重ねても、段ごとにたどる。
#[test]
fn 再公開を2段重ねてもたどる() {
    let 根 = ソース("crates/a/src/lib.rs", "mod 中;\npub use 中::位置;\n");
    let 中 = ソース("crates/a/src/中.rs", "mod 奥;\npub use self::奥::位置;\n");
    let 奥 = ソース("crates/a/src/中/奥.rs", 内部可変性を持つ定義);
    let 実装 = ソース("crates/a/src/使う.rs", "use crate::位置;\nimpl M不変データ for 位置 {}\n");
    内部可変性の違反だけが出る(vec![根, 中, 奥, 実装]);
}

/// 反証: 起点の予約語の無いパスを外部クレートのパスとして読むと、子のモジュールの定義を見つけられない。
#[test]
fn 起点の予約語の無い取り込みは子のモジュールからの相対として読む() {
    let 根 = ソース("crates/a/src/lib.rs", "mod 内;\nuse 内::位置;\nimpl M不変データ for 位置 {}\n");
    let 内 = ソース("crates/a/src/内.rs", 内部可変性を持つ定義);
    内部可変性の違反だけが出る(vec![根, 内]);
}

/// 反証: 子のモジュールとして在らない最初の区切りを相対として読むと、外部クレートの型を自分のクレートの型と取り違える。
#[test]
fn 子のモジュールとして無い最初の区切りは外部クレートとして読む() {
    let 根 = ソース("crates/a/src/lib.rs", "use 他::位置;\nimpl M不変データ for 位置 {}\n");
    let 他 = ソース("crates/他/src/lib.rs", 内部可変性を持つ定義);
    内部可変性の違反だけが出る(vec![根, 他]);
}
