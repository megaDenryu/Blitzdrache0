//! `クレート構文検査` の口のうち、設計解釈マーカーを実装した型の実装が、その型の定義と同じファイルにあるかを調べるもの。返すのは違反でなく警告の一覧である。
//! 触るのは `ソース一覧` だけであり、`違反一覧` には触れない。
//! 設計解釈マーカーを実装した型の `impl` を別のファイルに書くと、書き手はマーカーを見ないまま型を書き換えうる。マーカーが目に入らない場所で実装を書こうとしている書き手(AI)に気づかせるため、警告にする(終了コードは変えない)。
//! 設計解釈マーカーを実装した型は、`設計解釈マーカーの実装` の一覧から求める。調べる範囲は、その型と同じクレートの `src` にある実装の見出し(固有の `impl`・トレイトの実装・`unsafe impl`・設計解釈マーカーの実装そのもの)のすべてである。
//! 実装の対象の型のパスの最後の名前が設計解釈マーカーを実装した型の名前と一致すれば、同じ型とみなす。型の意味を解析せず名前だけで判定するため、同じクレートにある同じ名前の別の型の実装にも警告が出る。その場合、書き手は警告を無視してよい。
//! 名前が付いていない対象(全称の実装 `impl<T> トレイト for T`)は調べない。正本 `blitz_design` が持つ標準の `Result` への包括の実装は、設計解釈マーカーを実装した型に数えない。
//! 参照: `_doc/設計/設計オントロジー.md` 2.5.3

use std::collections::HashMap;
use std::ffi::{OsStr, OsString};
use std::path::{Path, PathBuf};

use super::super::warning::警告;
use super::impl_header::implの見出しを読む;
use super::line_matching::クレート名;
use super::syntax_checker::クレート構文検査;
use super::trait_implementation::設計解釈マーカーの実装;
use super::type_definition::定義ブロックの結果;
use super::設計解釈マーカーの一覧::設計解釈マーカー;

/// 設計解釈マーカーを実装した型1つの、定義のファイルと実装した設計解釈マーカー。同じクレートに同じ名前の型が複数あれば、定義のファイルも複数並ぶ。
#[derive(Default)]
struct 型の定義のファイルと実装したマーカー {
    定義のファイル一覧: Vec<PathBuf>,
    マーカー一覧: Vec<設計解釈マーカー>, // 見つけた順であり、同じマーカーは1回だけ並ぶ
}

impl 型の定義のファイルと実装したマーカー {
    fn 足す(&mut self, マーカー: 設計解釈マーカー, 定義のファイル: PathBuf) {
        if !self.定義のファイル一覧.contains(&定義のファイル) {
            self.定義のファイル一覧.push(定義のファイル);
        }
        if !self.マーカー一覧.contains(&マーカー) {
            self.マーカー一覧.push(マーカー);
        }
    }

    fn 定義のファイルか(&self, パス: &Path) -> bool {
        self.定義のファイル一覧.iter().any(|定義のファイル| 定義のファイル == パス)
    }

    fn 定義のファイルの外にある実装の説明(&self, 型名: &str) -> String {
        let マーカー = self.マーカー一覧.iter().map(|マーカー| format!("`{}`", マーカー.名前())).collect::<Vec<_>>().join("・");
        let 定義のファイル = self.定義のファイル一覧.iter().map(|パス| パス.display().to_string()).collect::<Vec<_>>().join("・");
        format!(
            "型 `{型名}` には設計解釈マーカー({マーカー})が付いていますが、この `impl` は定義のファイル({定義のファイル})とは別のファイルにあります。マーカーが目に入らない場所で実装を書くと、マーカーが課す法則(`M不変データ` なら、自分の値を書き換えないこと)を見落としやすくなります。この `impl` を {定義のファイル} へ移してください。なお、この警告は型の名前だけを見て判定しています。この `impl` が同じ名前の別の型のものであれば、この警告は無視してください。"
        )
    }
}

/// 設計解釈マーカーを実装した型の定義のファイルと実装したマーカーを、クレートの名前と型の名前から探す表。
#[derive(Default)]
struct 設計解釈マーカーを実装した型の定義の置き場 {
    クレートごと: HashMap<OsString, HashMap<String, 型の定義のファイルと実装したマーカー>>,
}

impl 設計解釈マーカーを実装した型の定義の置き場 {
    fn 足す(&mut self, 実装: &設計解釈マーカーの実装, 定義のファイル: PathBuf) {
        let クレート = クレート名(&定義のファイル).to_os_string();
        self.クレートごと.entry(クレート).or_default().entry(実装.型名.clone()).or_default().足す(実装.マーカー, 定義のファイル);
    }

    fn 型を探す(&self, クレート: &OsStr, 型名: &str) -> Option<&型の定義のファイルと実装したマーカー> {
        self.クレートごと.get(クレート)?.get(型名)
    }
}

impl クレート構文検査 {
    /// 設計解釈マーカーを実装した型と同じクレートにある実装の見出しのうち、その型の定義のファイルの外にあるものの警告。見出しの行で報告する。
    pub fn 設計解釈マーカーを実装した型の定義のファイルの外にある実装の警告一覧(&self) -> Vec<警告> {
        let 置き場 = self.設計解釈マーカーを実装した型の定義の置き場を作る();
        let mut 警告一覧 = Vec::new();
        for (パス, 行一覧) in &self.ソース一覧 {
            for 添字 in 0..行一覧.len() {
                let Some(構文) = implの見出しを読む(行一覧, 添字).and_then(|見出し| 見出し.構文を読む()) else {
                    continue;
                };
                if 構文.全称の実装か() {
                    continue;
                }
                let Some(型) = 置き場.型を探す(クレート名(パス), 構文.対象.名前()) else {
                    continue;
                };
                if !型.定義のファイルか(パス) {
                    警告一覧.push(警告::行単位(パス.clone(), 添字 + 1, 型.定義のファイルの外にある実装の説明(構文.対象.名前())));
                }
            }
        }
        警告一覧
    }

    // すべての設計解釈マーカーの実装を1件ずつ見て、定義が一意に見つかった型の定義のファイルと実装したマーカーを置き場へ足す。定義が見つからない型は別の違反になるため、ここでは数えない。
    fn 設計解釈マーカーを実装した型の定義の置き場を作る(&self) -> 設計解釈マーカーを実装した型の定義の置き場 {
        let mut 置き場 = 設計解釈マーカーを実装した型の定義の置き場::default();
        for 実装 in 設計解釈マーカー::全部の一覧().into_iter().flat_map(|マーカー| self.設計解釈マーカーの実装一覧(マーカー)) {
            if 実装.正本の標準resultへの包括の実装か() {
                continue;
            }
            if let 定義ブロックの結果::見つかった { パス, .. } = self.型の定義ブロック(&実装) {
                置き場.足す(&実装, パス);
            }
        }
        置き場
    }
}
