//! 宣言の見出し(`impl`・`trait`・`fn` の書き出しから本体か引数の並びまでの表記)を1文字ずつ読み、どの括弧の中に居るかを数える状態。
//! 型引数の山括弧・丸括弧・角括弧と、型引数の中の定数式の波括弧を数え、本体を開く波括弧と引数の並びを開く丸括弧を、括弧の中のものと区別して答える。
//! `->` の `>` は山括弧を閉じない。関数の型(`FnOnce(&mut Self) -> T`)と戻り値の型を書いた見出しで山括弧の数を狂わせないためである。

/// 1文字を読んだときに、その文字がどの括弧の中でもない位置で開いた括弧の区別。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 最上位で開いた括弧 {
    本体の波括弧,
    引数の丸括弧,
    無し,
}

#[derive(Default)]
pub struct 見出しの括弧の深さ {
    山: usize,
    丸: usize,
    角: usize,
    式の波: usize,
    直前: Option<char>,
}

impl 見出しの括弧の深さ {
    /// どの括弧の中でもない位置に居るか。
    pub const fn 最上位か(&self) -> bool {
        self.山 == 0 && self.丸 == 0 && self.角 == 0 && self.式の波 == 0
    }

    /// 1文字を読んで深さを進める。どの括弧の中でもない位置で本体の `{` か引数の `(` を開いたなら、そう答える。
    pub fn 一文字読む(&mut self, 文字: char) -> 最上位で開いた括弧 {
        let 最上位か = self.最上位か();
        let 開いた括弧 = match 文字 {
            _ if self.式の波 > 0 => {
                self.定数式の中を読む(文字);
                最上位で開いた括弧::無し
            }
            '{' if 最上位か => 最上位で開いた括弧::本体の波括弧,
            '(' if 最上位か => {
                self.丸 += 1;
                最上位で開いた括弧::引数の丸括弧
            }
            _ => {
                self.括弧を数える(文字);
                最上位で開いた括弧::無し
            }
        };
        self.直前 = Some(文字);
        開いた括弧
    }

    /// 1文字を読んで深さを進める。どの括弧の中でもない位置の `{` と `(` も、本体や引数の並びの始まりとして区別せず括弧として数える。
    /// 引数の並びを分けるときに、構造体のパターン(`規則 { 値: x, 他: y }`)の中のカンマと `:` を最上位と取り違えないために使う。
    pub fn 括弧として数える(&mut self, 文字: char) {
        if self.式の波 > 0 {
            self.定数式の中を読む(文字);
        } else {
            self.括弧を数える(文字);
        }
        self.直前 = Some(文字);
    }

    // 型引数の中の定数式(`境界<{ 1 }>`)の波括弧だけを数える。式の中の山括弧は比較の演算子でありうるため数えない。
    fn 定数式の中を読む(&mut self, 文字: char) {
        match 文字 {
            '{' => self.式の波 += 1,
            '}' => self.式の波 = self.式の波.saturating_sub(1),
            _ => {}
        }
    }

    fn 括弧を数える(&mut self, 文字: char) {
        match 文字 {
            '<' => self.山 += 1,
            '>' if self.直前 != Some('-') => self.山 = self.山.saturating_sub(1),
            '(' => self.丸 += 1,
            ')' => self.丸 = self.丸.saturating_sub(1),
            '[' => self.角 += 1,
            ']' => self.角 = self.角.saturating_sub(1),
            '{' => self.式の波 = 1,
            _ => {}
        }
    }
}

/// 表記を、どの括弧の中でもない位置のカンマで分ける。型引数の並びと関数の引数の並びを1つずつに分けるために使う。波括弧(構造体のパターンと定数式)の中のカンマでは分けない。
pub fn 最上位のカンマで分ける(表記: &str) -> Vec<&str> {
    let mut 括弧 = 見出しの括弧の深さ::default();
    let mut 区切り一覧 = Vec::new();
    let mut 始まり = 0;
    for (位置, 文字) in 表記.char_indices() {
        if 文字 == ',' && 括弧.最上位か() {
            区切り一覧.push(&表記[始まり..位置]);
            始まり = 位置 + 1;
        }
        括弧.括弧として数える(文字);
    }
    区切り一覧.push(&表記[始まり..]);
    区切り一覧
}
