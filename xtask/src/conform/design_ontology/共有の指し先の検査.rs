//! `クレート構文検査` の説明関数のうち、純粋データ規約の対象の型(2つの基底の契約とデータの役割を名乗る型)が持つ共有の指し先を検査するもの。
//! 持ってよい共有の指し先は、`M共有される不変データ` を名乗る型を指す `Arc<型>` だけである(設計オントロジー 2.5.3 の共通の法則3)。
//! `Rc` と `Weak` は持てない。`Arc` の中身が `M共有される不変データ` を名乗らない型であるか、1つの名前として読めないか、定義を一意にたどれないときも違反にする。
//! 借りる参照 `&` は別の検査(`pure_data_definition_law.rs`)が違反にする。規則を借りると規則が地図より長く生きられず、値として持ち運べなくなるためである。
//! 中身の型は、その表記を書いた行の位置から型の定義の探索でたどり、たどり着いた型の同一性(定義の位置のモジュール + 型名)が `M共有される不変データ` の実装の型の同一性の一覧にあるかで判定する。
//! 定義が見つからない型は、純粋データ規約の検査が別の違反にするため、ここでは報告しない。

use std::collections::HashSet;

use super::line_matching::{名前で読める表記, 波括弧が閉じる行, 語として現れるか};
use super::module_path::モジュールパス;
use super::syntax_checker::クレート構文検査;
use super::syntax_patterns::型定義のシグネチャ;
use super::trait_implementation::設計解釈マーカーの実装;
use super::type_definition::{型の在り処の問い, 定義ブロックの結果};
use super::共有の指し先の表記::{共有の指し先, 行の共有の指し先一覧};
use super::設計解釈マーカーの一覧::設計解釈マーカー;

impl クレート構文検査 {
    /// 純粋データ規約の対象の型の定義が持つ共有の指し先が、どれも `M共有される不変データ` を名乗る型を指す `Arc` であること。
    pub fn 純粋データの共有の指し先が共有される不変データだけを指すこと(mut self) -> Self {
        let 共有の同一性一覧: HashSet<(モジュールパス, String)> = self.設計解釈マーカーの実装一覧(設計解釈マーカー::M共有される不変データ).iter().map(|型| self.型の同一性(型)).collect();
        let 違反一覧: Vec<_> = self.純粋データ規約の対象一覧().into_iter().map(|型| (self.共有の指し先の違反一覧(&型, &共有の同一性一覧), 型)).collect();
        for (説明一覧, 型) in 違反一覧 {
            for 説明 in 説明一覧 {
                self.違反にする(&型, 説明);
            }
        }
        self
    }

    // 型の定義の宣言の行から本体を閉じる行までの共有の指し先を、行ごとに判定する。
    fn 共有の指し先の違反一覧(&self, 型: &設計解釈マーカーの実装, 共有の同一性一覧: &HashSet<(モジュールパス, String)>) -> Vec<String> {
        let 定義ブロックの結果::見つかった { パス, モジュール, .. } = self.型の定義ブロック(型) else {
            return Vec::new();
        };
        let Some((_, 行一覧)) = self.ソース一覧.iter().find(|(候補, _)| *候補 == パス) else {
            return Vec::new();
        };
        let 字句位置一覧 = モジュールパス::ファイルのパスから求める(&パス).行ごとの字句位置一覧(行一覧);
        let シグネチャ一覧 = 型定義のシグネチャ(&型.型名);
        let Some(宣言の位置) = 行一覧.iter().zip(&字句位置一覧).position(|(行, 位置)| シグネチャ一覧.iter().any(|宣言| 語として現れるか(行, 宣言)) && 位置.モジュール == モジュール) else {
            return Vec::new();
        };
        let 終了 = 波括弧が閉じる行(行一覧, 宣言の位置);
        let mut 説明一覧 = Vec::new();
        for (添字, 行) in 行一覧.iter().enumerate().take(終了 + 1).skip(宣言の位置) {
            for 指し先 in 行の共有の指し先一覧(行) {
                let 問いの位置 = 表記を書いた位置 { パス: &パス, 行番号: 添字 + 1 };
                説明一覧.extend(self.指し先の違反の説明(指し先, 問いの位置, 共有の同一性一覧));
            }
        }
        説明一覧
    }

    // 共有の指し先1件を判定し、違反なら説明を返す。
    fn 指し先の違反の説明(&self, 指し先: 共有の指し先, 位置: 表記を書いた位置<'_>, 共有の同一性一覧: &HashSet<(モジュールパス, String)>) -> Option<String> {
        let 中身の型の表記 = match 指し先 {
            共有の指し先::参照を数える別の指し先 { 名前 } => {
                return Some(format!("の定義は共有の指し先 `{名前}` を持てません。持てる共有の指し先は `M共有される不変データ` を名乗る型を指す `Arc` だけです"));
            }
            共有の指し先::Arc { 中身の型の表記 } => 中身の型の表記,
        };
        let Some(型名) = 名前で読める表記(&中身の型の表記) else {
            return Some(format!("の定義の `Arc<{中身の型の表記}>` の中身を1つの名前として読めない。`Arc` の中身には `M共有される不変データ` を名乗る型の名前をそのまま書く"));
        };
        let 問い = 型の在り処の問い {
            型名: &型名,
            参照元のパス: 位置.パス,
            参照元の行番号: 位置.行番号,
        };
        let 定義ブロックの結果::見つかった { モジュール, .. } = self.型の在り処を探す(&問い) else {
            return Some(format!("の定義の `Arc<{型名}>` の中身 `{型名}` の定義を一意にたどれない"));
        };
        let 説明 = format!("の定義の `Arc<{型名}>` の中身 `{型名}` が `M共有される不変データ` を名乗っていない。持てる共有の指し先は `M共有される不変データ` を名乗る型を指す `Arc` だけです");
        (!共有の同一性一覧.contains(&(モジュール, 型名))).then_some(説明)
    }
}

// 共有の指し先の表記を書いた行の位置。中身の型の定義を、この行から見える名前としてたどる。
#[derive(Clone, Copy)]
struct 表記を書いた位置<'a> {
    パス: &'a std::path::Path,
    行番号: usize,
}
