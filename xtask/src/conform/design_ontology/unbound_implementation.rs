//! 対象の型を決められない実装(全称の実装とマクロの本体の中の実装と関数)のうち、自己変更を与える関数を持つものを集める工程。
//! `自己変更の検査` の2つ目の問いであり、受け取るのは無し、返すのは見つけた実装の一覧である。触るのは全ソースとトレイトの宣言の索引とモジュールの索引だけである。
//! 全称の実装は境界を評価できず、マクロの中の実装は対象の型がメタ変数(`$型`)であるため、検査器はどちらも `M不変データ` の型へ結び付けられない。
//! マクロの本体の中の `impl` の外の関数も、そのマクロを本体の直下で呼んだ実装の型へ生えるため、同じく結び付けられない(`macro_body.rs`)。
//! そのため自分の型(全称の実装なら型引数、マクロの中ならメタ変数か `Self`)への可変参照を持つ関数を見つけたら黙って通さず、台帳(`unbound_implementation_ledger.rs`)と突き合わせる。

use std::collections::BTreeSet;
use std::path::PathBuf;

use super::super::violation::違反;
use super::function_signature::自己変更を問う対象;
use super::impl_header::implの見出しを読む;
use super::macro_body::マクロの本体;
use super::mutable_impl_scan::自己変更の検査;
use super::read_implementation::読んだ実装;
use super::self_modification_evidence::自己変更の根拠;

/// 対象の型を決められず、自己変更を与える関数を持つ実装1件。見出しは台帳の行と照らす鍵であり、実装なら本体を開く `{` の手前までを空白の並びを1つに揃えた表記、
/// マクロの本体の中の `impl` の外の関数なら `macro_rules! マクロ名 の fn 関数名` である。
pub struct 対象の型を決められない実装 {
    pub パス: PathBuf,
    pub 見出し: String,
    行番号: usize,
    根拠: 自己変更の根拠,
}

impl 対象の型を決められない実装 {
    pub fn 違反にする(&self) -> 違反 {
        let 説明 = format!(
            "設計オントロジー: 対象の型を決められない実装 `{}` {}。全称の実装とマクロの中の実装は検査器が M不変データ の型へ結び付けられないため違反にする。M不変データ の型に当たらないなら、その理由を台帳へ書く",
            self.見出し,
            self.根拠.説明()
        );
        違反::行単位(self.パス.clone(), self.行番号, 説明)
    }
}

impl 自己変更の検査<'_> {
    /// 走査範囲の全称の実装とマクロの本体の中の実装と関数のうち、自己変更を与える関数を持つものの一覧。マーカーの名前一覧は、マクロの本体の中の `impl` の外の関数へ問う相手の種である。
    pub fn 対象の型を決められない自己変更の実装一覧(&self, マーカーの名前一覧: &[String]) -> Vec<対象の型を決められない実装> {
        let 問う名前一覧 = self.マクロの中で問う名前一覧(マーカーの名前一覧);
        self.ソース一覧
            .iter()
            .flat_map(|(パス, 行一覧)| self.ファイルの中の対象の型を決められない実装一覧(読んだファイル { パス, 行一覧 }, &問う名前一覧))
            .collect()
    }

    // マクロの本体の中の `impl` の外の関数へ問う名前。生えた先の受け手を指す `Self` と、マーカーを名乗る型の名前の閉包である。
    fn マクロの中で問う名前一覧(&self, マーカーの名前一覧: &[String]) -> Vec<String> {
        let mut 一覧 = BTreeSet::from(["Self".to_string()]);
        for 名前 in マーカーの名前一覧 {
            一覧.extend(self.名前の辺一覧.閉包(名前));
        }
        一覧.into_iter().collect()
    }

    fn ファイルの中の対象の型を決められない実装一覧(&self, ファイル: 読んだファイル, 問う名前一覧: &[String]) -> Vec<対象の型を決められない実装> {
        let マクロの本体一覧 = マクロの本体::ファイルから集める(ファイル.行一覧);
        let mut 一覧: Vec<対象の型を決められない実装> = マクロの本体一覧.iter().flat_map(|マクロ| ファイル.マクロの中の実装の外の関数一覧(マクロ, 問う名前一覧)).collect();
        for 開始 in 0..ファイル.行一覧.len() {
            let Some(見出し) = implの見出しを読む(ファイル.行一覧, 開始) else {
                continue;
            };
            let Some(構文) = 見出し.構文を読む() else {
                continue;
            };
            if !構文.全称の実装か() && !マクロの本体一覧.iter().any(|マクロ| マクロ.行を含むか(開始)) {
                continue;
            }
            let 対象 = 自己変更を問う対象 {
                型名: 構文.対象.名前(),
                可変参照を対象にするか: 構文.対象.可変参照か,
            };
            let 揃えた見出し = 見出し.台帳の鍵の表記();
            let 実装 = 読んだ実装 {
                パス: ファイル.パス,
                行一覧: ファイル.行一覧,
                行番号: 開始 + 1,
                見出し,
            };
            if let Some(根拠) = self.実装が与える自己変更の根拠(&実装, &構文.種類, &対象) {
                一覧.push(対象の型を決められない実装 {
                    パス: ファイル.パス.clone(),
                    見出し: 揃えた見出し,
                    行番号: 開始 + 1,
                    根拠,
                });
            }
        }
        一覧
    }
}

// 走査する1つのファイル。パスとコードだけの行の一覧の組である。
struct 読んだファイル<'a> {
    パス: &'a PathBuf,
    行一覧: &'a [String],
}

impl 読んだファイル<'_> {
    // マクロの本体の中の `impl` の外にある、自己変更を与える関数1つずつを、対象の型を決められない実装1件にする。
    fn マクロの中の実装の外の関数一覧(&self, マクロ: &マクロの本体, 問う名前一覧: &[String]) -> Vec<対象の型を決められない実装> {
        let 関数一覧 = マクロ.実装の外の自己変更の関数一覧(self.行一覧, 問う名前一覧);
        関数一覧
            .into_iter()
            .map(|関数| 対象の型を決められない実装 {
                パス: self.パス.clone(),
                見出し: format!("macro_rules! {} の fn {}", マクロ.名前, 関数.署名.名前),
                行番号: 関数.行 + 1,
                根拠: 自己変更の根拠::実装の関数 {
                    パス: self.パス.clone(),
                    行番号: 関数.行 + 1,
                    対象の名前: 関数.対象の名前,
                    関数名: 関数.署名.名前,
                },
            })
            .collect()
    }
}
