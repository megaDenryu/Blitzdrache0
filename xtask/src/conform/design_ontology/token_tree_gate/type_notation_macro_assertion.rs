//! 実装の対象の型と型の別名の右辺に、どの深さにでもマクロの呼び出し(`名前` の後ろに `!` と括弧の群が続く形)を書かないことを確かめる純粋な工程。
//! 受け取るのは字句の木の一覧、返すのは違反一覧である。自己変更の禁止の検査は実装を型の名前で集めるが、マクロを展開した先の型の名前は字面に現れない。
//! 先頭のマクロの呼び出し(`impl 変更 for 型名!()`)だけを禁じていたとき、型引数の中に書いた `impl 変更 for Vec<型名!()>` は、読み口と字句の木の両方が同じに読むため突き合わせも違反を出さず、`規則` の自己変更を検査から落としていた。
//! 数えるのは、字句の木から取り出した行の頭の `impl` と `type` の見出しの中身(`header_tokens.rs`)である。群の中の字句も開いて持つため、深さによらず当たる。
//! 行の頭でない宣言は、読み口と字句の木の突き合わせ(`item_keyword_reconciliation.rs`)が別に違反にするため、行の頭の見出しだけを見れば足りる。
//! 括弧の群の手前の `!` の前が識別子であれば数えるため、定数式の中の `if !(..)` も数える。厳しくなる向きの誤りだけである。走査範囲の現状は0件である。

use std::path::Path;

use super::super::super::violation::違反;
use super::token_tree_index::字句の木の一覧;

/// 実装の対象の型か型の別名の右辺でマクロを呼ぶ宣言の違反一覧。並びはパスの順、ファイルの中では原文の順である。字句の木へ変えられなかったファイルは、その違反が別に出るため数えない。
pub fn 型の表記の中のマクロの呼び出しの違反一覧(字句の木: &字句の木の一覧) -> Vec<違反> {
    字句の木
        .数えたファイルの一覧()
        .flat_map(|(パス, 数えた)| {
            数えた
                .行の頭の見出し一覧
                .iter()
                .filter(|見出し| 見出し.中身.型の表記にマクロの呼び出しを含むか())
                .map(move |見出し| マクロの呼び出しの違反(パス, 見出し.行番号))
        })
        .collect()
}

fn マクロの呼び出しの違反(パス: &Path, 行番号: usize) -> 違反 {
    let 説明 = "設計オントロジー: 実装の対象の型か型の別名の右辺の中でマクロを呼んでいる(`impl 変更 for Vec<型名!()>`・`type 包み = [型名!(); 1];`)。検査器はマクロを展開できず、展開した先の型の名前が字面に現れないため、自己変更の禁止の検査がその実装を名前で集められない。深さによらず違反にする。マクロを呼ばずに型を書く".to_string();
    違反::行単位(パス.to_path_buf(), 行番号, 説明)
}

#[cfg(test)]
mod tests {
    use super::super::super::normal_form_test_entry::{原文, 正規形の説明関数を連ねた違反の説明一覧};

    fn マクロの違反の件数(本文: &str) -> usize {
        正規形の説明関数を連ねた違反の説明一覧(vec![原文("crates/a/src/x.rs", 本文)])
            .iter()
            .filter(|説明| 説明.contains("右辺の中でマクロを呼んでいる"))
            .count()
    }

    #[test]
    fn 実装の対象と型の別名の右辺のどの深さのマクロの呼び出しも違反にする() {
        for 本文 in [
            "impl 変更 for 型名!() {}\n",
            "impl 変更 for Vec<型名!()> {}\n",
            "impl 変更 for &mut 型名!() {}\n",
            "impl 変更 for (u8, Option<a::型名![]>) {}\n",
            "pub type 包み = [型名!(); 1];\n",
            "type 包み<T> = Result<T, 型名! {}>;\n",
        ] {
            assert_eq!(マクロの違反の件数(本文), 1, "{本文}");
        }
    }

    #[test]
    fn マクロを呼ばない表記とトレイトと本体のマクロは違反にしない() {
        let 本文 = "impl 変更 for Vec<規則> {\n    fn 数える(&self) -> usize {\n        vec![1].len()\n    }\n}\nimpl !Send for 規則 {}\ntype 別名 = fn() -> !;\n";
        assert_eq!(マクロの違反の件数(本文), 0);
    }
}
