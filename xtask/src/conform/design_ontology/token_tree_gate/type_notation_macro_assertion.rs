//! 実装の見出しの全体(型引数の並び・トレイト・対象の型・`where` 句)と型の別名の宣言(型引数の並びと右辺)に、どの深さにでもマクロの呼び出し(`名前` の後ろに `!` と括弧の群が続く形)を書かないことを確かめる工程。
//! 受け取るのは字句の木の一覧(違反一覧を作るとき)か、字句の木の並びと予約語の添字(字句の木を数えるとき)、返すのは違反一覧か、その宣言の見出しがマクロを呼ぶかである。
//! 自己変更の禁止の検査は、実装を対象の型の表記と型引数の並びの境界と `where` 句に現れる型の名前で集めるが、マクロを展開した先の型の名前は字面に現れない。
//! 実装の対象の型と型の別名の右辺だけを見ていたとき、境界に書いた `impl<T: DerefMut<Target = 目標!()>> 変更 for Vec<T>` と、`where` 句に書いた同じ境界は、`規則` を書き換えるのに検査から落ちていた。
//! 数えるのは、行の頭の `impl` の後ろから、山括弧の外の本体の波括弧の群までの字句と、行の頭の `type` の後ろから、山括弧の外の `;` までの字句である。群の中の字句も開いて持つため、深さによらず当たる。
//! 行の頭でない宣言は、読み口と字句の木の突き合わせ(`item_keyword_reconciliation.rs`)が別に違反にするため、行の頭の見出しだけを見れば足りる。
//! 括弧の群の手前の `!` の前が識別子であれば数えるため、定数式の中の `if !(..)` も数える。厳しくなる向きの誤りだけである。走査範囲の現状は0件である。

use std::path::Path;

use proc_macro2::{Delimiter, TokenTree};

use super::super::super::violation::違反;
use super::angle_bracket_scan::{最上位で止める, 記号か};
use super::item_keyword_position::項目の予約語;
use super::normalized_token_sequence::正規化した字句の並び;
use super::token_tree_index::字句の木の一覧;

/// 並びの添字の行の頭の予約語が `impl` か `type` で、その見出しの全体のどこかでマクロを呼ぶか。`impl` は本体の波括弧の群の手前まで、`type` は宣言を終える `;` の手前までを見る。
pub fn 見出しでマクロを呼ぶか(字句一覧: &[TokenTree], 添字: usize, 予約語: 項目の予約語) -> bool {
    let 後ろ = 字句一覧.get(添字 + 1..).unwrap_or_default();
    let 見出し = match 予約語 {
        項目の予約語::実装 => 最上位で止める(後ろ, |字句| matches!(字句, TokenTree::Group(群) if 群.delimiter() == Delimiter::Brace)),
        項目の予約語::型の別名 => 最上位で止める(後ろ, |字句| 記号か(字句, ';')),
        項目の予約語::取り込み | 項目の予約語::マクロの定義 => return false,
    };
    正規化した字句の並び::字句から作る(見出し).マクロの呼び出しを含むか()
}

/// 見出しの全体でマクロを呼ぶ `impl` と `type` の違反一覧。並びはパスの順、ファイルの中では原文の順である。字句の木へ変えられなかったファイルは、その違反が別に出るため数えない。
pub fn 型の表記の中のマクロの呼び出しの違反一覧(字句の木: &字句の木の一覧) -> Vec<違反> {
    字句の木
        .数えたファイルの一覧()
        .flat_map(|(パス, 数えた)| 数えた.見出しでマクロを呼ぶ宣言の行一覧.iter().map(move |行番号| マクロの呼び出しの違反(パス, *行番号)))
        .collect()
}

fn マクロの呼び出しの違反(パス: &Path, 行番号: usize) -> 違反 {
    let 説明 = "設計オントロジー: 実装の見出し(型引数の並び・トレイト・対象の型・`where` 句)か型の別名の宣言の中でマクロを呼んでいる(`impl 変更 for Vec<型名!()>`・`impl<T: DerefMut<Target = 目標!()>> 変更 for Vec<T>`・`type 包み = [型名!(); 1];`)。検査器はマクロを展開できず、展開した先の型の名前が字面に現れないため、自己変更の禁止の検査がその実装を名前で集められない。深さによらず違反にする。マクロを呼ばずに型を書く".to_string();
    違反::行単位(パス.to_path_buf(), 行番号, 説明)
}

#[cfg(test)]
mod tests {
    use super::super::super::normal_form_test_entry::{原文, 正規形の説明関数を連ねた違反の説明一覧};

    fn マクロの違反の件数(本文: &str) -> usize {
        正規形の説明関数を連ねた違反の説明一覧(vec![原文("crates/a/src/x.rs", 本文)]).iter().filter(|説明| 説明.contains("の中でマクロを呼んでいる")).count()
    }

    #[test]
    fn 実装の対象と型の別名の右辺のどの深さのマクロの呼び出しも違反にする() {
        for 本文 in [
            "impl 変更 for 型名!() {}\n",
            "impl 変更 for Vec<型名!()> {}\n",
            "impl 変更 for &mut 型名!() {}\n",
            "impl 変更 for (u8, Option<a::型名![]>) {}\n",
            "pub type 包み = [型名!(); 1];\n",
            "type 包み<T> = Result<T, 型名! {}>;\n",
        ] {
            assert_eq!(マクロの違反の件数(本文), 1, "{本文}");
        }
    }

    #[test]
    fn マクロを呼ばない表記とトレイトと本体のマクロは違反にしない() {
        let 本文 = "impl 変更 for Vec<規則> {\n    fn 数える(&self) -> usize {\n        vec![1].len()\n    }\n}\nimpl !Send for 規則 {}\ntype 別名 = fn() -> !;\n";
        assert_eq!(マクロの違反の件数(本文), 0);
    }
}
