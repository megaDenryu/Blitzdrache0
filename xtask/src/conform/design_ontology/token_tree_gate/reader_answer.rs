//! 1つのファイルについて、4つの読み口(`use`・`type`・`impl`・`macro_rules!`)が、どの行のどの予約語の宣言をどう読んだかを答える純粋な関数。受け取るのはコードだけの行の一覧、返すのは読み口の答えの一覧である。
//! 読み口は行の頭の宣言だけを読み、1つの行の1つの予約語について高々1つの宣言を読む。字句の木の予約語の現れとの突き合わせ(`readable_form_assertion.rs`)が、この答えを行と種類ごとに数える。
//! 読めた宣言・辺を作らない宣言・読み切れない宣言のどれも、読み口が答えた宣言として数える。読み切れない宣言は、それ自体が別の違反になるためである。

use super::super::declaration_reading_outcome::{宣言を読んだ結末, 読めない宣言};
use super::super::impl_header::implの見出しを読む;
use super::super::line_matching::implの予約語より後ろ;
use super::super::macro_body::マクロの本体;
use super::super::type_alias_scan::型の別名の宣言を読む;
use super::super::use_resolution::書き出しの行付きの取り込みの項目一覧;
use super::item_keyword_position::項目の予約語;

/// 読み口が1つの宣言を読んだ結末。
pub enum 読み口の結末 {
    読めた,
    辺を作らない宣言を読んだ,
    読めない(読めない宣言),
}

/// 読み口の答え1件。行番号は1始まりであり、予約語を書いた行である。
pub struct 読み口の答え {
    pub 行番号: usize,
    pub 予約語: 項目の予約語,
    pub 結末: 読み口の結末,
}

/// 1つのファイルの、4つの読み口の答えの一覧。並びは読み口ごとに行の順である。
pub fn ファイルの読み口の答え一覧(行一覧: &[String]) -> Vec<読み口の答え> {
    let 答え = |添字: usize, 予約語, 結末| 読み口の答え { 行番号: 添字 + 1, 予約語, 結末 };
    let 取り込み = 書き出しの行付きの取り込みの項目一覧(行一覧);
    let mut 一覧: Vec<読み口の答え> = 取り込み.読めた文の書き出しの行一覧.into_iter().map(|添字| 答え(添字, 項目の予約語::取り込み, 読み口の結末::読めた)).collect();
    一覧.extend(取り込み.読めない一覧.into_iter().map(|在り処| 答え(在り処.行番号 - 1, 項目の予約語::取り込み, 読み口の結末::読めない(在り処.宣言))));
    一覧.extend(マクロの本体::ファイルから集める(行一覧).iter().map(|本体| 答え(本体.書き出しの行(), 項目の予約語::マクロの定義, 読み口の結末::読めた)));
    for (添字, 行) in 行一覧.iter().enumerate() {
        match 型の別名の宣言を読む(行一覧, 添字) {
            宣言を読んだ結末::その宣言でない => {}
            宣言を読んだ結末::読めた(_) => 一覧.push(答え(添字, 項目の予約語::型の別名, 読み口の結末::読めた)),
            宣言を読んだ結末::辺を作らない宣言を読んだ => 一覧.push(答え(添字, 項目の予約語::型の別名, 読み口の結末::辺を作らない宣言を読んだ)),
            宣言を読んだ結末::読めない(宣言) => 一覧.push(答え(添字, 項目の予約語::型の別名, 読み口の結末::読めない(宣言))),
        }
        if implの予約語より後ろ(行).is_some() {
            let 結末 = match implの見出しを読む(行一覧, 添字) {
                Some(_) => 読み口の結末::読めた,
                None => 読み口の結末::読めない(読めない宣言 {
                    綴り: 行.trim().to_string(),
                    理由: "`impl` の見出しの本体を開く `{` が、そのファイルの中に見つからない",
                }),
            };
            一覧.push(答え(添字, 項目の予約語::実装, 結末));
        }
    }
    一覧
}
