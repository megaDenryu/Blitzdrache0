//! 生の識別子(`r#名前`)が予約語の名前だけを名乗ることを確かめる純粋な工程。受け取るのは字句の木の一覧、返すのは予約語でない名前に `r#` を付けた現れの違反一覧である。
//! 検査器の読み口と名前の閉包は、名前を字面のまま照らす。予約語でない名前を `r#` 付きで書くと(`use crate::x::r#規則 as 法則;`)、`規則` と同じ型を指すのに別の名前として読まれ、名前の閉包の辺と実装が落ちる。
//! `r#` が要るのは予約語を識別子として使うときだけであるため、予約語でない名前の `r#` を違反にする。予約語の一覧は Rust の参照が定める厳格な予約語と将来のための予約語(2024年版)である。走査範囲の現状は0件である。
//! `クレート構文検査` の説明関数にしないのは、この工程が読むのは字句の木の一覧だけであり、コードだけの行の一覧を持つ型に中身を積み増す理由が無いためである。

use std::path::Path;

use super::super::super::violation::違反;
use super::token_tree_index::字句の木の一覧;

const 予約語の一覧: [&str; 53] = [
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "Self", "static", "struct", "super", "trait", "true",
    "type", "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen", "_",
];

/// 予約語でない名前に `r#` を付けた生の識別子の違反一覧。並びはパスの順、ファイルの中では原文の順である。字句の木へ変えられなかったファイルは、その違反が別に出るため数えない。
pub fn 予約語でない名前の生の識別子の違反一覧(字句の木: &字句の木の一覧) -> Vec<違反> {
    字句の木
        .数えたファイルの一覧()
        .flat_map(|(パス, 数えた)| {
            数えた
                .生の識別子一覧
                .iter()
                .filter(|現れ| !予約語の一覧.contains(&現れ.名前.as_str()))
                .map(move |現れ| 予約語でない生の識別子の違反(パス, 現れ.行番号, &現れ.名前))
        })
        .collect()
}

fn 予約語でない生の識別子の違反(パス: &Path, 行番号: usize, 名前: &str) -> 違反 {
    let 説明 = format!("設計オントロジー: 生の識別子 `r#{名前}` は予約語でない名前に `r#` を付けている。検査器は名前を字面のまま照らすため、`{名前}` と同じものを指すのに別の名前として読み、名前の閉包の辺と実装を黙って落とす。`r#` を外して書く");
    違反::行単位(パス.to_path_buf(), 行番号, 説明)
}
