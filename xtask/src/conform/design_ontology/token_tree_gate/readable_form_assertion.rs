//! `クレート構文検査` の説明関数のうち、検査器が項目の宣言を読み切ったことを確かめるもの。触るのは `ソース一覧` と `違反一覧` と、受け取った字句の木の一覧だけである。
//! 自己変更の禁止の検査は、`use`・`type`・`impl`・`macro_rules!` の4つの読み口だけで名前の辺と実装を集める。読み口が読まなかった宣言と読み切れなかった宣言は、その `use` が持ち込む名前と、その `type` が作る辺と、その `impl` の本体の関数を、違反にも件数にもせずに検査から落とす。
//! そのため、この説明関数は4つを1箇所で違反にする。読み口が読み切れなかった宣言と、字句の木が数えた項目を始めうる予約語と読み口の答えが食い違う行(`item_keyword_reconciliation.rs`)と、字句の木へ変えられなかったファイルと、シバンで始まるファイルである。
//! 根拠はグローバルCLAUDE.md「検査器は解析できなかった入力を黙って対象から外してはならない」である。走査範囲に現状0件であり、この規約は0件を保つためのものである。

use std::path::{Path, PathBuf};

use super::super::super::violation::違反;
use super::super::declaration_reading_outcome::{読めない宣言, 読めない宣言の在り処};
use super::super::syntax_checker::クレート構文検査;
use super::item_keyword_reconciliation::読み口と食い違った現れ一覧;
use super::reader_answer::{ファイルの読み口の答え一覧, 読み口の結末};
use super::token_tree_index::字句の木の一覧;
use super::token_tree_scan::ファイルの字句の木;

impl クレート構文検査 {
    /// 項目の宣言のうち、検査器が読み切れないものと読まないものが1つも無いこと。
    pub fn 読み切れない宣言が無いこと(mut self, 字句の木: &字句の木の一覧) -> Self {
        let 該当一覧: Vec<違反> = self.ソース一覧.iter().flat_map(|(パス, 行一覧)| ファイルの読み切れない宣言の違反一覧(パス, 行一覧, 字句の木.ファイルの字句の木(パス))).collect();
        self.違反一覧.extend(該当一覧);
        self
    }
}

// 1つのファイルの、読み切れない宣言と読まなかった予約語と字句の木へ変えられなかったことの違反。並びは行の順である。
fn ファイルの読み切れない宣言の違反一覧(パス: &Path, 行一覧: &[String], 字句の木: Option<&ファイルの字句の木>) -> Vec<違反> {
    let 答え一覧 = ファイルの読み口の答え一覧(行一覧);
    let mut 一覧: Vec<(usize, 違反)> = Vec::new();
    match 字句の木 {
        Some(ファイルの字句の木::数えた(数えた)) => {
            一覧.extend(読み口と食い違った現れ一覧(&数えた.予約語の現れ一覧, &答え一覧).into_iter().map(|現れ| (現れ.行番号, 現れ.違反にする(パス.to_path_buf()))));
        }
        Some(ファイルの字句の木::変えられない { 行番号, 桁 }) => 一覧.push((*行番号, 字句の木へ変えられない違反(パス, *行番号, *桁))),
        Some(ファイルの字句の木::シバンで始まる) => 一覧.push((1, シバンの違反(パス))),
        None => 一覧.push((
            1,
            違反::行単位(
                PathBuf::from(パス),
                1,
                "設計オントロジー: このファイルの字句の木を数えていない。項目を始めうる予約語を読み口の答えと突き合わせられないため違反にする".to_string(),
            ),
        )),
    }
    for 答え in 答え一覧 {
        if let 読み口の結末::読めない(宣言) = 答え.結末 {
            一覧.push((答え.行番号, 読めない違反(パス, 答え.行番号, 宣言)));
        }
    }
    一覧.sort_by_key(|(行番号, _)| *行番号);
    一覧.into_iter().map(|(_, 違反)| 違反).collect()
}

fn 読めない違反(パス: &Path, 行番号: usize, 宣言: 読めない宣言) -> 違反 {
    読めない宣言の在り処 { 行番号, 宣言 }.違反にする(パス)
}

fn シバンの違反(パス: &Path) -> 違反 {
    let 説明 =
        "設計オントロジー: このファイルはシバン(`#!` で始まり3文字目が `[` でない行)で始まる。rustc はシバンの行を読み飛ばすが、検査器の字句の木と読み口はその行を同じ規則で読み飛ばせず、行の中の宣言を食い違って読むため違反にする。シバンを消す"
            .to_string();
    違反::行単位(PathBuf::from(パス), 1, 説明)
}

fn 字句の木へ変えられない違反(パス: &Path, 行番号: usize, 桁: usize) -> 違反 {
    let 説明 = format!("設計オントロジー: 検査器がこのファイルを字句の木へ変えられない({行番号}行{桁}桁)。字句の木へ変えられないファイルは、項目を始めうる予約語を数えられず、読み口が読まない宣言を見落とすため違反にする");
    違反::行単位(PathBuf::from(パス), 行番号, 説明)
}
