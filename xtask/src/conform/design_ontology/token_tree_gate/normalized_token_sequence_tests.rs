//! 空白とコメントの違いを消した字句の並び(`normalized_token_sequence.rs`)の試験。表記の違いを消すことと、深さによらないマクロの呼び出しと、関数の引数の外の可変参照を見つけることを固定する。

use super::normalized_token_sequence::正規化した字句の並び;

#[test]
fn 空白とコメントと文字列の違いを消し表記の途中で切れた表記は字句へ分けない() {
    let 詰めた = 正規化した字句の並び::表記から作る("包み<{ 1 },規則>");
    assert_eq!(詰めた, 正規化した字句の並び::表記から作る("包み < { 1 } ,\n 規則 /* 注 */ >"));
    assert_eq!(正規化した字句の並び::表記から作る("S<'<'>"), 正規化した字句の並び::表記から作る("S<>"));
    assert_ne!(正規化した字句の並び::表記から作る("[u8; 4]"), 正規化した字句の並び::表記から作る("[u8; 5]"));
    assert!(正規化した字句の並び::表記から作る("包み<{ const fn 一() -> usize").is_none());
}

#[test]
fn 深さによらずマクロの呼び出しを見つけ否定の演算子と不等号は数えない() {
    for 表記 in ["型名!()", "Vec<型名!()>", "[a::型名! [ ]; 1]", "包み<(u8, $m!{})>"] {
        assert!(正規化した字句の並び::表記から作る(表記).is_some_and(|並び| 並び.マクロの呼び出しを含むか()), "{表記}");
    }
    for 表記 in ["Vec<規則>", "包み<{ 1 != 2 }>", "fn() -> !", "包み<{ !(true) as usize }>"] {
        assert!(正規化した字句の並び::表記から作る(表記).is_some_and(|並び| !並び.マクロの呼び出しを含むか()), "{表記}");
    }
}

#[test]
fn 関数の引数の外の深さによらない可変参照を見つけ関数の引数の中と共有の参照は数えない() {
    for 表記 in [
        "&'a mut 規則",
        "Option<&mut 規則>",
        "Box<&&mut 規則>",
        "fn() -> &'static mut 規則",
        "Box<dyn FnMut(&mut u8) -> &'static mut 規則>",
        "Pin<&'a mut 規則>",
    ] {
        assert!(正規化した字句の並び::表記から作る(表記).is_some_and(|並び| 並び.関数の引数の外に可変参照を含むか()), "{表記}");
    }
    for 表記 in ["fn(&mut 規則) -> u8", "Box<dyn FnMut(&mut 規則, fn(&mut u8))>", "&'a 規則", "Pin<Box<規則>>", "*mut 規則"] {
        assert!(正規化した字句の並び::表記から作る(表記).is_some_and(|並び| !並び.関数の引数の外に可変参照を含むか()), "{表記}");
    }
}
