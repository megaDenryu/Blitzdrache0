//! 読み口が読んだ行の頭の `impl` と `type` の見出しの中身を、字句の木から取り出した見出しの中身と突き合わせる純粋な関数。受け取るのは字句の木の見出しの一覧と読み口の答えの一覧、返すのは食い違った見出しの行番号と違反の組の一覧である。
//! 予約語の数の突き合わせ(`item_keyword_reconciliation.rs`)は、読み口が宣言を読んだかだけを見て、どう読んだかを見ない。読み口が識別子の文字や `for` の位置を読み違えると、実装の対象の名前や型引数を取り違えたまま数だけが釣り合い、
//! その実装が自己変更の検査から落ちる(`impl<T·x: M不変データ> 変更 for T·x`・`impl 型·for { .. }`・`impl M不変データ for::jibun::規則 {}`)。そのため、同じ行の同じ予約語の見出しを両方が読んだなら、中身が等しくなければ違反にする。
//! 中身は名前だけでなく、対象の型の表記と型の別名の右辺の全体を持つ。パスの最後の名前が一致したまま表記の途中で切れた読み(型引数の定数式の中の `where` で切る形)も食い違いとして捕まえるためである。
//! 片方だけが見出しを読んだ行は、数の突き合わせが別に違反にする。読み口が読み切れなかった宣言も、それ自体が別の違反になるため突き合わせない。

use std::path::Path;

use super::super::super::violation::違反;
use super::reader_answer::{読み口の答え, 読み口の結末};
use super::token_tree_scan::行の頭の見出し;

/// 同じ行の同じ予約語の見出しを、読み口と字句の木が違う中身に読んだものの違反一覧。行番号は1始まりであり、並びは読み口の答えの順である。
pub fn 見出しの中身が食い違った違反一覧(パス: &Path, 見出し一覧: &[行の頭の見出し], 答え一覧: &[読み口の答え]) -> Vec<(usize, 違反)> {
    答え一覧
        .iter()
        .filter_map(|答え| {
            let 読み口の結末::見出しを読めた(読み口の中身) = &答え.結末 else {
                return None;
            };
            let 字句の木の中身 = &見出し一覧.iter().find(|見出し| 見出し.行番号 == 答え.行番号 && 見出し.予約語 == 答え.予約語)?.中身;
            (字句の木の中身 != 読み口の中身).then(|| {
                let 説明 = format!(
                    "設計オントロジー: この行の `{}` の見出しを、検査器の読み口と字句の木が違う中身に読んだ(読み口は {}、字句の木は {})。読み口が名前を読み違えると、実装の対象や名前の辺を取り違えたまま自己変更の検査から黙って落とすため違反にする。見出しを識別子と空白と括弧の素直な並びで書く",
                    答え.予約語.表記(),
                    読み口の中身.説明の表記(),
                    字句の木の中身.説明の表記(),
                );
                (答え.行番号, 違反::行単位(パス.to_path_buf(), 答え.行番号, 説明))
            })
        })
        .collect()
}
