//! 型の別名と関連型の右辺(`type 名前 = 右辺;`)に、関数の型の引数の外のどの深さにでも可変参照(`&mut X`・`&'a mut X`)を書かないことを確かめる純粋な工程。
//! 受け取るのは字句の木の一覧、返すのは違反一覧である。自己変更の禁止の検査は、可変参照を対象にする実装と、関数の可変の受け手と引数を、字面の `&` と `mut` で見分ける(`impl_syntax/target_type.rs`・`parameter_form.rs`)。
//! 別名が可変参照を隠すと、`type 可変<'a> = &'a mut 規則;` の下の `impl 変更 for 可変<'_> { fn 変える(self) { .. } }` と、固有の実装の `fn 変える(値: 可変<'_>)`・`self: 可変<'_>` が字面の可変参照を持たず、検査から落ちる。
//! 関連型(`impl 領域 for 甲 { type 状態 = &'static mut 規則; }`)も、射影 `<甲 as 領域>::状態` を型引数の中に書けば同じく隠す。この正規形があれば可変参照は必ず字面に現れ、字面の判定がそのまま健全になる。
//! 関数の型と `Fn` 系のトレイトの引数(`fn(&mut 規則)`・`FnMut(&mut 規則)`)の中は数えない。引数の位置の可変参照は、その関数の値を持つ側へ書き換える相手を与えないためであり、関数の引数の型の判定(`parameter_form/mutable_reference_in_type.rs`)と同じ扱いである。
//! 数えるのは、字句の木から取り出した行の頭の `type` の見出しの中身(`header_tokens.rs`)であり、項目の別名も実装とトレイトの本体の中の関連型も同じく当たる。行の頭でない宣言は突き合わせ(`item_keyword_reconciliation.rs`)が別に違反にする。
//! 共有の参照(`&'a 規則`)と `Pin` は禁じない。走査範囲の現状は、関数の引数の外に可変参照を書いた右辺が0件であり、共有の参照と `Pin` を禁じると関数の引数の中の共有の参照5件と `Pin<Box<dyn Future ..>>` の1件が違反になるためである。
//! 共有の参照を隠した別名はマーカーの実装の対象の参照の禁止(`impl_syntax/target_form.rs`)を抜けるが、共有の参照は指す値の書き換えを与えない。

use std::path::Path;

use super::super::super::violation::違反;
use super::token_tree_index::字句の木の一覧;

/// 型の別名か関連型の右辺に可変参照を書いた宣言の違反一覧。並びはパスの順、ファイルの中では原文の順である。字句の木へ変えられなかったファイルは、その違反が別に出るため数えない。
pub fn 型の別名の右辺の可変参照の違反一覧(字句の木: &字句の木の一覧) -> Vec<違反> {
    字句の木
        .数えたファイルの一覧()
        .flat_map(|(パス, 数えた)| {
            数えた
                .行の頭の見出し一覧
                .iter()
                .filter(|見出し| 見出し.中身.型の別名の右辺に可変参照を含むか())
                .map(move |見出し| 可変参照の違反(パス, 見出し.行番号, &見出し.中身.説明の表記()))
        })
        .collect()
}

fn 可変参照の違反(パス: &Path, 行番号: usize, 表記: &str) -> 違反 {
    let 説明 = format!(
        "設計オントロジー: 型の別名か関連型の右辺に可変参照を書いている({表記})。自己変更の禁止の検査は可変参照を字面の `&` と `mut` で見分けるため、別名が可変参照を隠すと、その別名を対象にした実装の値で受ける `self` と、別名で書いた受け手と引数の可変参照を見落とす。関数の型の引数(`fn(&mut 規則)`)の中は数えない。可変参照は使う位置へ直接書く"
    );
    違反::行単位(パス.to_path_buf(), 行番号, 説明)
}

#[cfg(test)]
mod tests {
    use super::super::super::normal_form_test_entry::{原文, 正規形の説明関数を連ねた違反の説明一覧};

    fn 可変参照の違反の件数(本文: &str) -> usize {
        正規形の説明関数を連ねた違反の説明一覧(vec![原文("crates/a/src/x.rs", 本文)])
            .iter()
            .filter(|説明| 説明.contains("右辺に可変参照を書いている"))
            .count()
    }

    #[test]
    fn 項目の別名と関連型の右辺のどの深さの可変参照も違反にする() {
        for 本文 in [
            "pub type 可変<'a> = &'a mut 規則;\n",
            "pub type 可変<'a, T> = &'a mut T;\n",
            "type 包み<'a> = Option<Box<&'a mut 規則>>;\n",
            "type 取る = fn() -> &'static mut 規則;\n",
            "type 固定<'a> = std::pin::Pin<&'a mut 規則>;\n",
            "impl 領域 for 甲 {\n    type 状態 = &'static mut 規則;\n}\n",
        ] {
            assert_eq!(可変参照の違反の件数(本文), 1, "{本文}");
        }
    }

    #[test]
    fn 関数の引数の中の可変参照と共有の参照とpinと右辺の無い関連型は違反にしない() {
        let 本文 = "type 読む = fn(&mut u8, &規則) -> u8;\ntype 閉包 = Box<dyn FnMut(&mut 規則)>;\ntype 共有<'a> = &'a 規則;\ntype 未来 = Pin<Box<dyn Future<Output = u8> + Send>>;\npub trait 領域 {\n    type 状態: Clone;\n}\n";
        assert_eq!(可変参照の違反の件数(本文), 0);
    }
}
