//! 走査範囲のファイルごとの字句の木の数え上げ(`token_tree_scan.rs`)を、パスで引ける形で持つ一覧。受け取るのはパスと原文、返すのはパスごとの数えた結末である。
//! 検査の入口(`scan_entry.rs`)は、コードだけの行の一覧と並べてこの一覧を作り、原文そのものは検査へ渡さない。検査が字句の木について知ってよいのは、項目を始めうる予約語と生の識別子の現れだけだからである。
//! パスの順に並べて持つのは、この一覧を走査する工程の違反の並びを、実行のたびに同じにするためである。

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use super::token_tree_scan::{ファイルの字句の木, 字句の木から数えた現れ};

/// ファイルごとの字句の木の数え上げの一覧。
#[derive(Default)]
pub struct 字句の木の一覧 {
    ファイルごと: BTreeMap<PathBuf, ファイルの字句の木>,
}

impl 字句の木の一覧 {
    /// 1つのファイルの原文を字句の木へ変えて数え、パスで引けるように足す。
    pub fn 原文を数えて足す(&mut self, パス: PathBuf, 原文: &str) {
        self.ファイルごと.insert(パス, ファイルの字句の木::原文から数える(原文));
    }

    /// パスのファイルの数えた結末。数えていないファイルなら無い。
    pub fn ファイルの字句の木(&self, パス: &Path) -> Option<&ファイルの字句の木> {
        self.ファイルごと.get(パス)
    }

    /// 字句の木へ変えられたファイルのパスと数えた現れの組の並び。並びはパスの順である。
    pub fn 数えたファイルの一覧(&self) -> impl Iterator<Item = (&Path, &字句の木から数えた現れ)> {
        self.ファイルごと.iter().filter_map(|(パス, 木)| match 木 {
            ファイルの字句の木::数えた(数えた) => Some((パス.as_path(), 数えた)),
            ファイルの字句の木::変えられない { .. } | ファイルの字句の木::シバンで始まる => None,
        })
    }
}
