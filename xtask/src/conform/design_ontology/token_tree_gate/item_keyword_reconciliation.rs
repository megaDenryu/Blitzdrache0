//! 字句の木が数えた項目を始めうる予約語の現れと、読み口の答えを、行と予約語の種類ごとの数で突き合わせる純粋な関数。受け取るのは現れの一覧と答えの一覧、返すのは読み口が読まなかった現れの一覧である。
//! ある行のある種類について、現れの数が答えの数を超えたら、超えた分は読み口が読まなかった宣言である。読み口は1つの行の1つの種類について高々1つの宣言しか読まないため、同じ行の2つ目の宣言(`impl A {} impl B {}`)は必ず超えた分になる。
//! 逆向きに、答えの数が現れの数を超えるのは、字句の木が項目を始めないと数えた位置の宣言を読み口が読んだときである。辺や実装を余分に集めるだけであり、安全側に倒れるため違反にしない。

use std::collections::BTreeMap;
use std::path::PathBuf;

use super::super::super::violation::違反;
use super::item_keyword_position::{予約語の現れた場所, 項目の予約語};
use super::reader_answer::読み口の答え;
use super::token_tree_scan::項目を始めうる予約語の現れ;

/// 読み口が読まなかった予約語の現れ。1つの行の1つの種類ごとに1件であり、行番号は1始まりである。
pub struct 読み口が読まなかった現れ {
    pub 行番号: usize,
    予約語: 項目の予約語,
    現れの数: usize,
    答えの数: usize,
    トークン木の中か: bool,
    メタ変数の位置か: bool,
}

/// 行と種類ごとに、現れの数が読み口の答えの数を超えたものの一覧。並びは行の順である。
pub fn 読み口が読まなかった現れ一覧(現れ一覧: &[項目を始めうる予約語の現れ], 答え一覧: &[読み口の答え]) -> Vec<読み口が読まなかった現れ> {
    let mut 答えの数: BTreeMap<(usize, 項目の予約語), usize> = BTreeMap::new();
    for 答え in 答え一覧 {
        *答えの数.entry((答え.行番号, 答え.予約語)).or_default() += 1;
    }
    let mut 現れの集計: BTreeMap<(usize, 項目の予約語), Vec<予約語の現れた場所>> = BTreeMap::new();
    for 現れ in 現れ一覧 {
        現れの集計.entry((現れ.行番号, 現れ.予約語)).or_default().push(現れ.場所);
    }
    現れの集計
        .into_iter()
        .filter_map(|((行番号, 予約語), 場所一覧)| {
            let 答えの数 = 答えの数.get(&(行番号, 予約語)).copied().unwrap_or(0);
            (場所一覧.len() > 答えの数).then(|| 読み口が読まなかった現れ {
                行番号,
                予約語,
                現れの数: 場所一覧.len(),
                答えの数,
                トークン木の中か: 場所一覧.iter().any(|場所| *場所 != 予約語の現れた場所::トークン木の外で項目を始めうる位置),
                メタ変数の位置か: 場所一覧.contains(&予約語の現れた場所::マクロのメタ変数の位置),
            })
        })
        .collect()
}

impl 読み口が読まなかった現れ {
    /// その1件の違反。読み口が読まない宣言は、違反にも件数にもならずに検査から落ちることを説明に書く。
    pub fn 違反にする(&self, パス: PathBuf) -> 違反 {
        let 表記 = self.予約語.表記();
        let トークン木の追記 = if self.トークン木の中か {
            "。マクロの呼び出しの引数と `macro_rules!` の本体の中では、マクロが字句を並べ替えて展開できるため、型の位置の予約語(`-> impl Trait`)も数える。避けるには行を分けて行の頭に書く"
        } else {
            ""
        };
        let メタ変数の追記 = if self.メタ変数の位置か {
            "。マクロのメタ変数の名前が予約語(`$type` 等)なら、名前を改める"
        } else {
            ""
        };
        let 説明 = format!(
            "設計オントロジー: この行に項目を始めうる `{表記}` が{}個あるが、検査器の読み口が読んだ宣言は{}個である。読み口が読むのは{}だけであり、それ以外の位置(行の途中・同じ行の2つ目・マクロの引数の中・コメントや改行を挟んだ形)の{}を黙って検査から落とすため、行を改めて行の頭に書く{トークン木の追記}{メタ変数の追記}",
            self.現れの数,
            self.答えの数,
            self.予約語.読み口が読む形(),
            self.予約語.読まないと落ちるもの(),
        );
        違反::行単位(パス, self.行番号, 説明)
    }
}
