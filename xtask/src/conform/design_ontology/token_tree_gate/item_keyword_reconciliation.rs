//! 字句の木が数えた項目を始めうる予約語の現れと、読み口の答えを、行と予約語の種類ごとに突き合わせる純粋な関数。受け取るのは現れの一覧と答えの一覧、返すのは食い違った行の一覧である。
//! 突き合わせは双方向の完全一致である。第一に、行の頭でない現れは、答えの数によらず違反にする。読み口は行の頭の宣言しか読まないため、行の途中の宣言(`impl A {} impl B {}` の2つ目)は必ず読まれずに落ちる。
//! 第二に、行の頭では、字句の木が項目を始めると見た現れの数と読み口の答えの数が等しくなければならない。字句の木だけが数える向きは、読み口が読まなかった宣言である。
//! 読み口だけが答える向きは、字句の木が項目を始めないと見た位置(`->` の次の行の型の位置の `impl`)を読み口が宣言と読んだものである。数だけで突き合わせると、この余分な答えが同じ行の読まれなかった現れを打ち消すため、この向きも違反にする。

use std::collections::BTreeMap;
use std::path::PathBuf;

use super::super::super::violation::違反;
use super::item_keyword_position::{予約語の現れた場所, 項目の予約語};
use super::reader_answer::読み口の答え;
use super::token_tree_scan::項目を始めうる予約語の現れ;

/// 字句の木の現れと読み口の答えが食い違った1つの行の1つの種類。行番号は1始まりである。
pub struct 読み口と食い違った現れ {
    pub 行番号: usize,
    予約語: 項目の予約語,
    数: 行と種類ごとの数,
}

// 1つの行の1つの種類について数えたもの。
#[derive(Default)]
struct 行と種類ごとの数 {
    行の頭の現れ: usize,
    行の途中の現れ: usize,
    答え: usize,
    トークン木の中か: bool,
    メタ変数の位置か: bool,
}

/// 行と種類ごとに、行の途中の現れがあるか、行の頭の現れの数と読み口の答えの数が違うものの一覧。並びは行の順である。
pub fn 読み口と食い違った現れ一覧(現れ一覧: &[項目を始めうる予約語の現れ], 答え一覧: &[読み口の答え]) -> Vec<読み口と食い違った現れ> {
    let mut 集計: BTreeMap<(usize, 項目の予約語), 行と種類ごとの数> = BTreeMap::new();
    for 答え in 答え一覧 {
        集計.entry((答え.行番号, 答え.予約語)).or_default().答え += 1;
    }
    for 現れ in 現れ一覧 {
        let 数 = 集計.entry((現れ.行番号, 現れ.予約語)).or_default();
        if 現れ.行の頭か {
            数.行の頭の現れ += 1
        } else {
            数.行の途中の現れ += 1
        }
        数.トークン木の中か |= 現れ.場所 != 予約語の現れた場所::トークン木の外で項目を始めうる位置;
        数.メタ変数の位置か |= 現れ.場所 == 予約語の現れた場所::マクロのメタ変数の位置;
    }
    集計
        .into_iter()
        .filter(|(_, 数)| 数.行の途中の現れ > 0 || 数.行の頭の現れ != 数.答え)
        .map(|((行番号, 予約語), 数)| 読み口と食い違った現れ { 行番号, 予約語, 数 })
        .collect()
}

impl 読み口と食い違った現れ {
    /// その1件の違反。読まれなかった宣言が検査から落ちることと、余分な答えが読まれなかった宣言を隠すことを説明に書く。
    pub fn 違反にする(&self, パス: PathBuf) -> 違反 {
        let 数 = &self.数;
        let 読まなかった説明 = if 数.行の途中の現れ > 0 || 数.行の頭の現れ > 数.答え {
            let トークン木の追記 = if 数.トークン木の中か {
                "。マクロの呼び出しの引数と `macro_rules!` の本体の中では、マクロが字句を並べ替えて展開できるため、型の位置の予約語(`-> impl Trait`)も数える。避けるには行を分けて行の頭に書く"
            } else {
                ""
            };
            let メタ変数の追記 = if 数.メタ変数の位置か {
                "。マクロのメタ変数の名前が予約語(`$type` 等)なら、名前を改める"
            } else {
                ""
            };
            format!(
                "読み口が読むのは{}だけであり、それ以外の位置(行の途中・同じ行の2つ目・マクロの引数の中・コメントや改行を挟んだ形)の{}を黙って検査から落とすため、行を改めて行の頭に書く{トークン木の追記}{メタ変数の追記}。",
                self.予約語.読み口が読む形(),
                self.予約語.読まないと落ちるもの(),
            )
        } else {
            String::new()
        };
        let 余分な説明 = if 数.行の頭の現れ < 数.答え {
            "読み口が行の頭で宣言と読んだものを、字句の木は項目を始める位置と数えない(`->` や `<` の後ろで行を改めた型の位置の予約語)。読み口が項目でないものを宣言と読むと、同じ行の読まれなかった宣言と数が釣り合って見落としを隠すため、その予約語を前の字句と同じ行に書く。"
        } else {
            ""
        };
        let 説明 = format!(
            "設計オントロジー: この行に項目を始めうる `{}` が{}個あるが、検査器の読み口が読んだ宣言は{}個である(行の頭の現れは{}個)。{読まなかった説明}{余分な説明}",
            self.予約語.表記(),
            数.行の頭の現れ + 数.行の途中の現れ,
            数.答え,
            数.行の頭の現れ,
        );
        違反::行単位(パス, self.行番号, 説明)
    }
}
