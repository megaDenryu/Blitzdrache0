//! 行の頭の `impl` と `type` の見出しから読んだ、読み口と字句の木の読みを突き合わせるための値。受け取るのは読み口の読んだ構文(読み口の側)か、字句の木から取り出した字句(`header_tokens.rs`)、返すのはこの値である。
//! 突き合わせる値は、自己変更の検査が実装と辺を集めるときに読む値そのものである。`impl` ではトレイトの実装か・対象の型のパスの最後の名前・対象の型の表記の全体・可変参照を対象にするか・型引数の名前の一覧、
//! `type` では別名・型引数の名前の一覧・右辺のパスの最後の名前・右辺の全体である。表記の全体は、空白とコメントの違いを消した字句の並び(`normalized_token_sequence.rs`)で比べる。
//! 名前は、1つの識別子(マクロのメタ変数なら頭の `$` を含む)で書けるときだけ持ち、それ以外(`[規則]`・`dyn 変更`・`&'a 規則`)は名前で読めないとする。読み口と字句の木のどちらも同じ規則で揃える。

use super::super::impl_syntax::実装の見出しの構文;
use super::super::line_matching::{パスの最後の名前, 名前で読める表記};
use super::super::type_alias_scan::型の別名の宣言;
use super::normalized_token_sequence::正規化した字句の並び;

/// 行の頭の宣言の見出しから読んだ、突き合わせに使う値。表記の全体は、読み口の表記を字句へ分けられなかったとき無い。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 見出しの中身 {
    実装 {
        トレイトの実装か: bool,
        対象の型の名前: Option<String>,
        対象の型の表記: Option<正規化した字句の並び>,
        可変参照を対象にするか: bool,
        型引数の名前一覧: Vec<String>,
    },
    右辺のある型の別名 {
        別名: String,
        型引数の名前一覧: Vec<String>,
        右辺の最後の名前: Option<String>,
        右辺: Option<正規化した字句の並び>,
    },
    右辺の無い型の別名,
}

impl 見出しの中身 {
    /// 読み口が読んだ実装の見出しの構文から。対象の型の表記は、自己変更の検査が名前を照らす表記(参照と `Pin` と囲みの丸括弧を外した後)である。
    pub fn 実装の見出しの構文から作る(構文: &実装の見出しの構文) -> Self {
        Self::実装 {
            トレイトの実装か: 構文.トレイトの表記().is_some(),
            対象の型の名前: 名前で読める表記(構文.対象.名前()),
            対象の型の表記: 正規化した字句の並び::表記から作る(構文.対象.表記()),
            可変参照を対象にするか: 構文.対象.可変参照か(),
            型引数の名前一覧: 構文.型引数の名前一覧().to_vec(),
        }
    }

    /// 読み口が読んだ型の別名の宣言から。右辺は、名前の閉包が辺を作るときに読む右辺の表記である。
    pub fn 型の別名の宣言から作る(宣言: &型の別名の宣言) -> Self {
        Self::右辺のある型の別名 {
            別名: 宣言.別名.clone(),
            型引数の名前一覧: 宣言.型引数の名前一覧(),
            右辺の最後の名前: 名前で読める表記(パスの最後の名前(&宣言.右辺)),
            右辺: 正規化した字句の並び::表記から作る(&宣言.右辺),
        }
    }

    /// 型の別名か関連型の右辺の、関数の型の引数の外のどの深さにでも可変参照があるか。型の別名の右辺に可変参照を書かない正規形(`alias_mutable_reference_assertion.rs`)が問う。
    pub fn 型の別名の右辺に可変参照を含むか(&self) -> bool {
        matches!(self, Self::右辺のある型の別名 { 右辺: Some(右辺), .. } if 右辺.関数の引数の外に可変参照を含むか())
    }

    /// 違反の説明に書く表記。
    pub fn 説明の表記(&self) -> String {
        let 名前 = |名前: &Option<String>| 名前.clone().unwrap_or_else(|| "名前で読めない".to_string());
        let 表記 = |表記: &Option<正規化した字句の並び>| 表記.as_ref().map_or_else(|| "字句へ分けられない".to_string(), |並び| format!("`{}`", 並び.説明の表記()));
        match self {
            Self::実装 {
                トレイトの実装か,
                対象の型の名前,
                対象の型の表記,
                可変参照を対象にするか,
                型引数の名前一覧,
            } => {
                let 種類 = if *トレイトの実装か { "トレイトの実装" } else { "固有の実装" };
                let 参照 = if *可変参照を対象にするか { "可変参照を対象にする" } else { "可変参照を対象にしない" };
                format!("{種類}・対象の型の名前は {}・対象の型の表記は {}・{参照}・型引数は [{}]", 名前(対象の型の名前), 表記(対象の型の表記), 型引数の名前一覧.join(", "))
            }
            Self::右辺のある型の別名 {
                別名,
                型引数の名前一覧,
                右辺の最後の名前,
                右辺,
            } => {
                format!("別名は {別名}・型引数は [{}]・右辺の最後の名前は {}・右辺は {}", 型引数の名前一覧.join(", "), 名前(右辺の最後の名前), 表記(右辺))
            }
            Self::右辺の無い型の別名 => "右辺の無い型の別名".to_string(),
        }
    }
}
