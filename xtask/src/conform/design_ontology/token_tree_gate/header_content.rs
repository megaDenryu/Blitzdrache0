//! 行の頭の `impl` と `type` の見出しから読んだ、読み口と字句の木の読みを突き合わせるための値。受け取るのは読み口の読んだ構文(読み口の側)か、字句の木から取り出した名前(`header_tokens.rs`)、返すのはこの値である。
//! 突き合わせる値は、自己変更の検査が名前で実装と辺を集めるときに使う値に限る。`impl` ではトレイトの実装か・対象の型のパスの最後の名前・型引数の名前の一覧、`type` では別名・型引数の名前の一覧・右辺のパスの最後の名前である。
//! 名前は、1つの識別子(マクロのメタ変数なら頭の `$` を含む)で書けるときだけ持ち、それ以外(`[規則]`・`dyn 変更`・`&'a 規則`)は名前で読めないとする。読み口と字句の木のどちらも同じ規則で揃える。

use super::super::impl_syntax::実装の見出しの構文;
use super::super::line_matching::{パスの最後の名前, 名前で読める表記};
use super::super::type_alias_scan::型の別名の宣言;

/// 行の頭の宣言の見出しから読んだ、突き合わせに使う値。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 見出しの中身 {
    実装 {
        トレイトの実装か: bool,
        対象の型の名前: Option<String>,
        型引数の名前一覧: Vec<String>,
    },
    右辺のある型の別名 {
        別名: String,
        型引数の名前一覧: Vec<String>,
        右辺の最後の名前: Option<String>,
    },
    右辺の無い型の別名,
}

impl 見出しの中身 {
    /// 読み口が読んだ実装の見出しの構文から。
    pub fn 実装の見出しの構文から作る(構文: &実装の見出しの構文) -> Self {
        Self::実装 {
            トレイトの実装か: 構文.トレイトの表記().is_some(),
            対象の型の名前: 名前で読める表記(構文.対象.名前()),
            型引数の名前一覧: 構文.型引数の名前一覧().to_vec(),
        }
    }

    /// 読み口が読んだ型の別名の宣言から。
    pub fn 型の別名の宣言から作る(宣言: &型の別名の宣言) -> Self {
        Self::右辺のある型の別名 {
            別名: 宣言.別名.clone(),
            型引数の名前一覧: 宣言.型引数の名前一覧(),
            右辺の最後の名前: 名前で読める表記(パスの最後の名前(&宣言.右辺)),
        }
    }

    /// 違反の説明に書く表記。
    pub fn 説明の表記(&self) -> String {
        let 名前 = |名前: &Option<String>| 名前.clone().unwrap_or_else(|| "名前で読めない".to_string());
        match self {
            Self::実装 {
                トレイトの実装か,
                対象の型の名前,
                型引数の名前一覧,
            } => {
                let 種類 = if *トレイトの実装か { "トレイトの実装" } else { "固有の実装" };
                format!("{種類}・対象の型の名前は {}・型引数は [{}]", 名前(対象の型の名前), 型引数の名前一覧.join(", "))
            }
            Self::右辺のある型の別名 {
                別名, 型引数の名前一覧, 右辺の最後の名前
            } => {
                format!("別名は {別名}・型引数は [{}]・右辺の最後の名前は {}", 型引数の名前一覧.join(", "), 名前(右辺の最後の名前))
            }
            Self::右辺の無い型の別名 => "右辺の無い型の別名".to_string(),
        }
    }
}
