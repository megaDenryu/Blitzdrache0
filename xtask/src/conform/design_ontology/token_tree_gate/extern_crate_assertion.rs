//! 走査範囲の `src` に `extern crate` の宣言を書かないことを確かめる純粋な工程。受け取るのは字句の木の一覧、返すのは `extern crate` の宣言の違反一覧である。
//! `extern crate self as jibun;` は、自分のクレートの根に別の名前を付け、`::jibun::規則` のように型名で始まらないパスで同じ型を指せるようにする。
//! 検査器は実装の対象の型の先頭の識別子を型名として読むため、このパスで書いた実装を種と定義の探索から落とす。Rust 2018 以降は依存のクレートを `extern crate` なしで使えるため、宣言そのものを禁じる。
//! 宣言を字句の木で数えるのは、`extern` と `crate` の間の改行やコメントで行単位の照合をすり抜けないためである。走査範囲の現状は0件である。

use std::path::Path;

use super::super::super::violation::違反;
use super::token_tree_index::字句の木の一覧;

/// `extern crate` の宣言の違反一覧。並びはパスの順、ファイルの中では原文の順である。字句の木へ変えられなかったファイルは、その違反が別に出るため数えない。
pub fn 外部クレートの宣言の違反一覧(字句の木: &字句の木の一覧) -> Vec<違反> {
    字句の木
        .数えたファイルの一覧()
        .flat_map(|(パス, 数えた)| 数えた.外部クレートの宣言の行一覧.iter().map(move |行番号| 外部クレートの宣言の違反(パス, *行番号)))
        .collect()
}

fn 外部クレートの宣言の違反(パス: &Path, 行番号: usize) -> 違反 {
    let 説明 = "設計オントロジー: `extern crate` を宣言している。`extern crate self as 名前;` はクレートの根に別の名前を付け、型名で始まらないパス(`::名前::規則`)で型を指せるようにするため、検査器が実装の対象の型名を読めず、その実装を検査から黙って落とす。宣言を消して `crate::` か依存のクレートの名前から書く".to_string();
    違反::行単位(パス.to_path_buf(), 行番号, 説明)
}
