//! 名前が当たった自己変更の実装のうち、同じ名前の別の型の実装であるものを除外する台帳。
//! 自己変更の禁止の検査は、マーカーを名乗る型の名前が対象の表記に識別子として現れる実装を全部集める過大近似である。
//! 区切られたドメインが違えば同じ表記が別の語でありうるため(`CLAUDE.md`「区切られたドメイン」)、同じ名前の別の型の実装がこの集まりへ現れうる。その1件を、別の型であるという理由を書いた行で除く。
//! 台帳に載っているのに該当しなくなった行は違反として報告し、台帳からの削除を強制する(`split_debt.rs`・`line_count_allowance.rs` の「台帳 + 陳腐化検査」と同じ様式)。
//! 参照: `_doc/設計/設計オントロジー.md` 2.5.3 の自己変更の禁止の読む範囲。

use std::path::{Path, PathBuf};

use super::super::violation::違反;
use super::name_matched_implementation::名前が当たった自己変更の実装;

/// 台帳の1行。マーカーの名前と、除外する実装のファイルのパスと見出しで1件を指す。除外する理由にはその実装が別の型のものである根拠を書き、陳腐化の違反の文言がそのまま読み手へ返す。
pub struct 台帳の行 {
    pub マーカーの名前: &'static str,
    pub パス: &'static str,
    pub 見出し: &'static str,
    pub 除外する理由: &'static str,
}

/// 注意: 行を足してよいのは、その実装が同じ名前の別の型のものであると示せるときだけである。2026-09-23 に走査範囲を調べた時点で該当する実装は無い。
const 登録済みの行一覧: [台帳の行; 0] = [];

pub struct 名前が当たった別の型の実装の台帳 {
    行一覧: Vec<台帳の行>,
}

impl 名前が当たった別の型の実装の台帳 {
    /// 本番の検査が使う、登録済みの行の台帳。
    pub fn 登録済みの台帳() -> Self {
        Self {
            行一覧: Vec::from(登録済みの行一覧)
        }
    }

    /// 試験が行を与えて組む台帳。
    #[cfg(test)]
    pub const fn 行一覧から組む(行一覧: Vec<台帳の行>) -> Self {
        Self { 行一覧 }
    }

    /// その1件を台帳が除くか。
    pub fn 除くか(&self, 検出: &名前が当たった自己変更の実装) -> bool {
        self.行一覧.iter().any(|行| 行.当たるか(検出))
    }

    /// 台帳に載っているのに、検出の一覧のどれにも当たらなくなった行の違反。
    pub fn 陳腐化の違反一覧(&self, 検出一覧: &[&名前が当たった自己変更の実装]) -> Vec<違反> {
        self.行一覧.iter().filter(|行| !検出一覧.iter().any(|検出| 行.当たるか(検出))).map(台帳の行::陳腐化の違反).collect()
    }
}

impl 台帳の行 {
    fn 当たるか(&self, 検出: &名前が当たった自己変更の実装) -> bool {
        検出.マーカーの名前 == self.マーカーの名前 && 台帳の表記へ揃える(&検出.パス) == self.パス && 検出.見出し == self.見出し
    }

    fn 陳腐化の違反(&self) -> 違反 {
        let 説明 = format!(
            "設計オントロジー: 名前が当たった別の型の実装の台帳に載っている `{}`(マーカーの名前 `{}`)が、自己変更を与える実装として見つからない(台帳から削除する。載せた理由は「{}」)",
            self.見出し, self.マーカーの名前, self.除外する理由
        );
        違反::ファイル単位(PathBuf::from(self.パス), 説明)
    }
}

// 走査で得るパスの区切り文字は実行環境で変わるため、斜線へ揃えてから台帳と照合する。
fn 台帳の表記へ揃える(パス: &Path) -> String {
    パス.to_string_lossy().replace('\\', "/")
}
