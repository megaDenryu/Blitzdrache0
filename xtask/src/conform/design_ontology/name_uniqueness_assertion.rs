//! `クレート構文検査` の説明関数のうち、検査器が名前で引く宣言を、別名が横から名乗らないように保つもの。触るのは `ソース一覧` と `違反一覧` だけである。
//! 自己変更の禁止の検査は、実装の対象の型もトレイトも名前で引く。`use … as` の別名が、走査範囲のトレイトの宣言の名前・取り込まずに書けるトレイトの名前・マーカーを名乗る型の名前のどれかを名乗ると、
//! 別の宣言の実装が、名前の上ではその宣言の実装として読めてしまう。そのためこの3つを名乗る別名を違反にする。走査範囲に現状0件であり、この規約は0件を保つためのものである。
//! 同じ名前の宣言が走査範囲に2つ以上あること自体は違反にしない。`CLAUDE.md`「区切られたドメイン」が、区切られたドメインが違えば同じ表記が別の語でありうると定めるためである。
//! そのとき検査器は、その名前を対象に含む実装を全部検査する(過大近似)。別の型の実装が違反として現れたら、台帳へ理由を書いて除く。

use std::path::PathBuf;

use super::super::violation::違反;
use super::prelude_trait_names::取り込まずに書けるトレイトの名前か;
use super::syntax_checker::クレート構文検査;
use super::syntax_patterns::オントロジートレイト;
use super::trait_name_index::トレイトの名前の索引;
use super::use_resolution::書き出しの行付きの取り込みの項目一覧;

impl クレート構文検査 {
    /// `use … as` の別名が、走査範囲のトレイトの宣言の名前・取り込まずに書けるトレイトの名前・マーカーを名乗る型の名前のどれも名乗らないこと。
    pub fn 取り込みの別名が宣言の名前を名乗っていないこと(mut self) -> Self {
        let 索引 = トレイトの名前の索引::全ソースから組む(&self.ソース一覧);
        let マーカーの型の名前一覧: Vec<String> = self.トレイト実装型一覧(オントロジートレイト::M不変データ).iter().map(|型| 型.対象の型のパスの最後の名前().to_string()).collect();
        let 該当一覧: Vec<(PathBuf, usize, String, &'static str)> = self
            .ソース一覧
            .iter()
            .flat_map(|(パス, 行一覧)| {
                書き出しの行付きの取り込みの項目一覧(行一覧)
                    .項目一覧
                    .into_iter()
                    .filter_map(|在り処| 在り処.項目.別名.clone().map(|別名| (在り処.書き出しの行, 別名)))
                    .filter_map(|(行, 別名)| 衝突した区分(&索引, &マーカーの型の名前一覧, &別名).map(|区分| (パス.clone(), 行 + 1, 別名, 区分)))
                    .collect::<Vec<_>>()
            })
            .collect();
        for (パス, 行番号, 別名, 区分) in 該当一覧 {
            let 説明 = format!("設計オントロジー: `use … as {別名}` の別名が{区分}と同じ名前である(自己変更の禁止の検査は名前で宣言を引くため、別名は名乗られていない名前にする)");
            self.違反一覧.push(違反::行単位(パス, 行番号, 説明));
        }
        self
    }
}

// その別名が名乗ってはならない名前と衝突するなら、衝突した区分の呼び名。
fn 衝突した区分(索引: &トレイトの名前の索引, マーカーの型の名前一覧: &[String], 別名: &str) -> Option<&'static str> {
    if マーカーの型の名前一覧.iter().any(|名前| 名前 == 別名) {
        return Some("マーカーを名乗る型の名前");
    }
    if 索引.宣言しているか(別名) {
        return Some("走査範囲のトレイトの宣言の名前");
    }
    取り込まずに書けるトレイトの名前か(別名).then_some("取り込まずに書けるトレイトの名前")
}
