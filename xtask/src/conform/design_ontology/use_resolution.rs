//! ファイルの `use` 行を読む工程。`use` 文を波括弧の群を入れ子ごと展開した項目の一覧に分ける。受け取るのはコードだけの行の一覧、返すのは読めた項目の一覧と読み切れない文の一覧である。
//! 群の展開そのものは `use_group_expansion.rs` が持つ。書かれたパスを絶対のモジュールパスにするのは、項目を読む側(`module_path.rs`)である。
//! 項目には、その `use` 文を書き出した行の添字を添える(モジュールの索引が項目を位置のモジュールへ振り分けるためである)。
//! 頭の属性と可視性(`pub`・`pub(crate)`・`pub(super)`・`pub(self)`・`pub(in パス)`)は、どれも `use` の接頭辞として読み飛ばす。
//! 1つの `use` 文の読み口は、`type` の読み口と同じく「その宣言でない」「読めた」「読み切れない」の3つだけを返す。ファイルの読み口は、それを読めた項目の一覧と読み切れない文の一覧の2つへ分けて返す。
//! 文は書き出しの行から最初の `;` までである(`use` の木は `;` を持てない)。読み切れない文(ファイルの最後まで `;` に届かない文と、展開しきれない群)は黙って飛ばさず、読み切れない宣言として返す。
//! 波括弧が1つも無い文でも、`;` に届かなければ読み切れない。読み口の全域性の検査(`readable_form_assertion.rs`)がそれを違反にする。

use super::declaration_prefix::属性と可視性を読み飛ばす;
use super::declaration_reading_outcome::{宣言を読んだ結末, 読めない宣言, 読めない宣言の在り処};
use super::statement_span::{セミコロンまで繋いだ本文, 宣言を終えるセミコロン};
use super::use_group_expansion::群を展開した項目一覧;

/// `use` 文を展開した1項目。書かれたパス(`crate::a::型`・`a::*`)と、`as` の別名を持つ。
pub struct 取り込みの項目 {
    pub パス: String,
    pub 別名: Option<String>,
}

/// 1つのファイルの中の取り込みの項目1件の在り処。書き出しの行はその `use` 文を書き出した行の0始まりの添字である。
pub struct 取り込みの項目の在り処 {
    pub 書き出しの行: usize,
    pub 項目: 取り込みの項目,
}

/// 1つのファイルの `use` 行を読んだ結果。読めた項目の一覧と、読み切れなかった文の一覧を持つ。
#[derive(Default)]
pub struct 読んだ取り込み一覧 {
    pub 項目一覧: Vec<取り込みの項目の在り処>,
    pub 読めない一覧: Vec<読めない宣言の在り処>,
}

impl 取り込みの項目 {
    /// 展開した1項目の表記(`a::b as c`)を、パスと別名へ分けて読む。パスか別名が空か空白を含むなら、1つの項目に読めないため無い。
    fn 表記から読む(表記: &str) -> Option<Self> {
        let (パス, 別名) = match 表記.split_once(" as ") {
            Some((パス, 別名)) => (パス.trim(), Some(別名.trim())),
            None => (表記.trim(), None),
        };
        let 一語か = |綴り: &str| !綴り.is_empty() && !綴り.contains(char::is_whitespace);
        (一語か(パス) && 別名.is_none_or(一語か)).then(|| Self {
            パス: パス.to_string(),
            別名: 別名.map(str::to_string),
        })
    }

    /// パスの最後の区切り(取り込んだ元の名前。glob の取り込みなら `*`)。
    pub fn 元の名前(&self) -> &str {
        self.パス.rsplit("::").next().unwrap_or_default().trim()
    }
}

/// 行の一覧の `use` 文を読み、読めた項目と読み切れなかった文に分ける。
pub fn 書き出しの行付きの取り込みの項目一覧(行一覧: &[String]) -> 読んだ取り込み一覧 {
    let mut 読んだ = 読んだ取り込み一覧::default();
    for 添字 in 0..行一覧.len() {
        match 取り込みの文を読む(行一覧, 添字) {
            宣言を読んだ結末::その宣言でない => {}
            宣言を読んだ結末::読めた(項目一覧) => 読んだ.項目一覧.extend(項目一覧.into_iter().map(|項目| 取り込みの項目の在り処 { 書き出しの行: 添字, 項目 })),
            宣言を読んだ結末::読めない(宣言) => 読んだ.読めない一覧.push(読めない宣言の在り処 { 行番号: 添字 + 1, 宣言 }),
        }
    }
    読んだ
}

// 添字の行が `use` 文を書き出すなら、最初の `;` まで行を繋いで波括弧の群を展開した項目の一覧。`;` に届かない文と展開しきれない群は読み切れない。
fn 取り込みの文を読む(行一覧: &[String], 添字: usize) -> 宣言を読んだ結末<Vec<取り込みの項目>> {
    let 書き出し = 行一覧.get(添字).map_or("", String::as_str).trim();
    let Some(残り) = 属性と可視性を読み飛ばす(書き出し).strip_prefix("use ") else {
        return 宣言を読んだ結末::その宣言でない;
    };
    let Some(本文) = セミコロンまで繋いだ本文(残り, 行一覧.get(添字 + 1..).unwrap_or_default(), 宣言を終えるセミコロン::最初の) else {
        return 宣言を読んだ結末::読めない(読めない宣言 {
            綴り: 書き出し.to_string(),
            理由: "`use` の文がファイルの最後まで `;` で終わっていない",
        });
    };
    match 群を展開した項目一覧(&本文) {
        Ok(表記一覧) => match 表記一覧.iter().map(|表記| 取り込みの項目::表記から読む(表記)).collect::<Option<Vec<_>>>() {
            Some(項目一覧) => 宣言を読んだ結末::読めた(項目一覧),
            None => 読み切れない文(&本文, "展開した項目が1つのパスと別名に読めない(空白を含む綴りがある)"),
        },
        Err(理由) => 読み切れない文(&本文, 理由),
    }
}

fn 読み切れない文(本文: &str, 理由: &'static str) -> 宣言を読んだ結末<Vec<取り込みの項目>> {
    宣言を読んだ結末::読めない(読めない宣言 {
        綴り: format!("use {};", 本文.trim()), 理由
    })
}
