//! `クレート構文検査` の説明関数のうち、`M命令の組` の法則「構造体であり、フィールドの型はどれも `Mコマンド` を名乗る」を検査するもの。
//! 命令の組とは、`Mコマンド` を名乗る型だけを名前付きのフィールドに並べた構造体のことである(設計オントロジー第2節。2026-09-28 の命令の組の裁定)。
//! 独立な選択の組を1つの列挙の選択肢へ掛け合わせて展開しないために置いた分類であり、定義が構造で決まるため、フィールドにコマンドでない値が混ざった型は命令の組でない。
//! フィールドの読み方と判定は `構造体のフィールドの読み取り.rs` が持つ。型の表記が1つの名前で読めないフィールド(`Vec<水平移動の操作>`・`Option<..>`・パスで修飾した名前)と、
//! 名前付きで並べていない本体は、`Mコマンド` を名乗る型そのものを並べた形と確かめられないため違反にする。

use super::syntax_checker::クレート構文検査;
use super::syntax_patterns::Rust型種別;
use super::構造体のフィールドの読み取り::{フィールドの判定, 構造体のフィールドの読み手, 構造体の本体の読み取り};
use super::設計解釈マーカーの一覧::設計解釈マーカー;

const 命令の組の形: &str = "命令の組は `Mコマンド` を名乗る型だけを名前付きのフィールドに並べた構造体である";

impl クレート構文検査 {
    /// `M命令の組` を実装する型が構造体であり、名前付きのフィールドを1つ以上持ち、どのフィールドの型も `Mコマンド` を名乗る型であること。定義が見つからない実装は別の違反にする。
    pub fn すべての命令の組がコマンドだけをフィールドに持つ構造体であること(mut self) -> Self {
        let mut 構造体の組 = Vec::new();
        for 組 in self.設計解釈マーカーの実装一覧(設計解釈マーカー::M命令の組) {
            if self.定義が見つからなければ違反にする(&組) {
                continue;
            }
            if !self.型種別を満たしているか(Rust型種別::Struct, &組) {
                self.違反にする(&組, "は struct 定義が必要です".to_string());
                continue;
            }
            構造体の組.push(組);
        }
        let 読み手 = 構造体のフィールドの読み手::生成する(&self);
        let 違反一覧: Vec<_> = 構造体の組.into_iter().map(|組| (命令の組の違反一覧(読み手.構造体のフィールドを読む(&組)), 組)).collect();
        for (説明一覧, 組) in 違反一覧 {
            for 説明 in 説明一覧 {
                self.違反にする(&組, 説明);
            }
        }
        self
    }
}

// 命令の組の本体の読み取りから、コマンドを名乗る型でないフィールドと、読めない本体の説明を組む。
fn 命令の組の違反一覧(読み取り: 構造体の本体の読み取り) -> Vec<String> {
    match 読み取り {
        構造体の本体の読み取り::構造体の宣言が無い => Vec::new(),
        構造体の本体の読み取り::行ごとの本体でない => {
            vec!["は名前付きのフィールドを行ごとに並べた本体を持つ構造体の定義が必要です(位置で並べたフィールドと1行に収めた本体は、フィールドの型を確かめられない)".to_string()]
        }
        構造体の本体の読み取り::フィールドが無い => vec![format!("はフィールドを1つも持たない。{命令の組の形}")],
        構造体の本体の読み取り::フィールドを判定した(判定一覧) => 判定一覧.into_iter().filter_map(フィールドの違反の説明).collect(),
    }
}

// フィールド1つの判定を、違反の説明へ写す。コマンドであるフィールドは違反でない。
fn フィールドの違反の説明(判定: フィールドの判定) -> Option<String> {
    match 判定 {
        フィールドの判定::コマンドである => None,
        フィールドの判定::コマンドでない { 名前, 型名 } => Some(format!("のフィールド `{名前}` の型 `{型名}` が `Mコマンド` を名乗っていない。{命令の組の形}")),
        フィールドの判定::名前と型として読めない { 行 } => Some(format!("の本体の行 `{行}` を `名前: 型` のフィールドとして読めない")),
        フィールドの判定::一つの名前として読めない { 名前, 型の表記 } => {
            Some(format!("のフィールド `{名前}` の型の表記 `{型の表記}` を1つの名前として読めない。命令の組は `Mコマンド` を名乗る型をそのままフィールドの型に書く"))
        }
        フィールドの判定::定義を一意にたどれない { 名前, 型名 } => Some(format!("のフィールド `{名前}` の型 `{型名}` の定義を一意にたどれない")),
    }
}
