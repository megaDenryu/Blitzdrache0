//! `クレート構文検査` の説明関数のうち、`M命令の組` の法則「構造体であり、フィールドの型はどれも `Mコマンド` を名乗る」を検査するもの。
//! 命令の組とは、同じ刻みに届いた命令の全体のことであり、独立な選択ごとの `Mコマンド` をフィールドに並べる。独立な選択の組を1つの列挙の選択肢へ
//! 掛け合わせて展開しないために置いた分類であるため、フィールドにコマンドでない値が混ざると、組は命令の全体でなくなる。
//! フィールドは、定義の本体の行を1行ずつ `名前: 型` として読む。型の表記を1つの名前として読み、その名前をフィールドの行の位置から型の定義の探索でたどり、
//! たどり着いた型の同一性(定義の位置のモジュール + 型名)が `Mコマンド` の実装の型の同一性の一覧にあるかで判定する。
//! 型の表記が1つの名前で読めないフィールド(`Vec<水平移動の操作>`・`Option<..>`・パスで修飾した名前)と、名前付きで並べていない本体は、
//! `Mコマンド` を名乗る型そのものを並べた形と確かめられないため違反にする。

use std::collections::HashSet;
use std::path::Path;

use super::line_matching::{名前で読める表記, 波括弧が閉じる行, 語として現れるか};
use super::module_path::モジュールパス;
use super::syntax_checker::クレート構文検査;
use super::syntax_patterns::{Rust型種別, 型宣言の開始};
use super::trait_implementation::設計解釈マーカーの実装;
use super::type_definition::{型の在り処の問い, 定義ブロックの結果};
use super::設計解釈マーカーの一覧::設計解釈マーカー;

impl クレート構文検査 {
    /// `M命令の組` を実装する型が構造体であり、名前付きのフィールドを1つ以上持ち、どのフィールドの型も `Mコマンド` を名乗る型であること。定義が見つからない実装は別の違反にする。
    pub fn すべての命令の組がコマンドだけをフィールドに持つ構造体であること(mut self) -> Self {
        let コマンドの同一性一覧: HashSet<(モジュールパス, String)> = self.設計解釈マーカーの実装一覧(設計解釈マーカー::Mコマンド).iter().map(|型| self.型の同一性(型)).collect();
        for 組 in self.設計解釈マーカーの実装一覧(設計解釈マーカー::M命令の組) {
            if self.定義が見つからなければ違反にする(&組) {
                continue;
            }
            if !self.型種別を満たしているか(Rust型種別::Struct, &組) {
                self.違反にする(&組, "は struct 定義が必要です".to_string());
                continue;
            }
            for 説明 in self.命令の組のフィールドの違反一覧(&組, &コマンドの同一性一覧) {
                self.違反にする(&組, 説明);
            }
        }
        self
    }

    // 命令の組の定義の本体を読み、コマンドを名乗る型でないフィールドと、読めない本体の説明を返す。
    fn 命令の組のフィールドの違反一覧(&self, 組: &設計解釈マーカーの実装, コマンドの同一性一覧: &HashSet<(モジュールパス, String)>) -> Vec<String> {
        let 定義ブロックの結果::見つかった { パス, モジュール, .. } = self.型の定義ブロック(組) else {
            return Vec::new();
        };
        let Some((_, 行一覧)) = self.ソース一覧.iter().find(|(候補, _)| *候補 == パス) else {
            return Vec::new();
        };
        let 字句位置一覧 = モジュールパス::ファイルのパスから求める(&パス).行ごとの字句位置一覧(行一覧);
        let 宣言の開始 = 型宣言の開始(Rust型種別::Struct, &組.型名);
        let Some(宣言の位置) = 行一覧.iter().zip(&字句位置一覧).position(|(行, 位置)| 語として現れるか(行, &宣言の開始) && 位置.モジュール == モジュール) else {
            return Vec::new();
        };
        // 本体を開いた波括弧が宣言の行で閉じない(閉じる行が宣言の行より後ろにある)ことで、名前付きのフィールドを行ごとに並べた本体と見分ける。
        let 終了 = 波括弧が閉じる行(行一覧, 宣言の位置);
        if 終了 == 宣言の位置 {
            return vec!["は名前付きのフィールドを行ごとに並べた本体を持つ構造体の定義が必要です(位置で並べたフィールドと1行に収めた本体は、フィールドの型を確かめられない)".to_string()];
        }
        let フィールドの行一覧: Vec<(usize, &str)> = 行一覧
            .iter()
            .enumerate()
            .take(終了)
            .skip(宣言の位置 + 1)
            .map(|(添字, 行)| (添字, 行.trim()))
            .filter(|(_, 行)| !行.is_empty() && !行.starts_with('#'))
            .collect();
        if フィールドの行一覧.is_empty() {
            return vec!["はフィールドを1つも持たない。命令の組は同じ刻みに届いた `Mコマンド` をフィールドに1つ以上並べる".to_string()];
        }
        フィールドの行一覧.into_iter().filter_map(|(添字, 行)| self.フィールドの違反(&パス, 添字, 行, コマンドの同一性一覧)).collect()
    }

    // フィールドの1行を読み、その型がコマンドを名乗る型でなければ説明を返す。
    fn フィールドの違反(&self, パス: &Path, 添字: usize, 行: &str, コマンドの同一性一覧: &HashSet<(モジュールパス, String)>) -> Option<String> {
        let Some((名前, 型の表記)) = フィールドの名前と型の表記(行) else {
            return Some(format!("の本体の行 `{行}` を `名前: 型` のフィールドとして読めない"));
        };
        let Some(型名) = 名前で読める表記(型の表記) else {
            return Some(format!("のフィールド `{名前}` の型の表記 `{型の表記}` を1つの名前として読めない。命令の組は `Mコマンド` を名乗る型をそのままフィールドの型に書く"));
        };
        let 問い = 型の在り処の問い {
            型名: &型名,
            参照元のパス: パス,
            参照元の行番号: 添字 + 1,
        };
        let 同一性 = match self.型の在り処を探す(&問い) {
            定義ブロックの結果::見つかった { モジュール, .. } => (モジュール, 型名),
            定義ブロックの結果::見つからない | 定義ブロックの結果::複数ある | 定義ブロックの結果::別名のため取り込み元を求められない => {
                return Some(format!("のフィールド `{名前}` の型 `{型名}` の定義を一意にたどれない"));
            }
        };
        (!コマンドの同一性一覧.contains(&同一性)).then(|| format!("のフィールド `{名前}` の型 `{}` が `Mコマンド` を名乗っていない。命令の組は同じ刻みに届いた1つの選択(`Mコマンド`)をフィールドに並べる", 同一性.1))
    }
}

// `pub 名前: 型,` の行から、名前と型の表記を読む。閉じ括弧の行と、名前と型の組でない行は読めないとして無い。
fn フィールドの名前と型の表記(行: &str) -> Option<(&str, &str)> {
    let (名前, 型の表記) = 可視性の前置きを落とす(行).split_once(':')?;
    let 型の表記 = 型の表記.trim().trim_end_matches(',').trim();
    (!名前.trim().is_empty() && !型の表記.is_empty() && !型の表記.starts_with(':')).then_some((名前.trim(), 型の表記))
}

// フィールドの行の頭の可視性(`pub`・`pub(crate)`・`pub(super)`・`pub(in パス)`)を落とす。括弧の付いた可視性は、閉じ括弧までを落とす。
// 括弧の中のパス(`pub(in crate::x)` の `::`)を名前と型の区切りの `:` と読まないため、区切りを探す前に落とす。
fn 可視性の前置きを落とす(行: &str) -> &str {
    if let Some((_, 後ろ)) = 行.strip_prefix("pub(").and_then(|括弧の中から| 括弧の中から.split_once(')')) {
        return 後ろ.trim_start();
    }
    行.strip_prefix("pub ").unwrap_or(行)
}
