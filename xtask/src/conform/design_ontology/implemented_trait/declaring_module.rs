//! 実装が書いたトレイトの表記から、そのトレイトの宣言を索引のどこで見るかを求める工程。受け取るのは読んだ実装とトレイトの表記とモジュールの索引とトレイトの宣言の索引、返すのは宣言の在り処である。
//! トレイトの同一性は宣言のモジュールパス + 名前である(`trait_declaration_index.rs`)。表記は、実装の対象の型と同じ規則(`module_index/name_location_search.rs`)で宣言のモジュールへ結び付ける。
//! 修飾のある表記(`甲::変更`・`crate::甲::変更`・`super::甲::変更`・`self::甲::変更`・`std::fmt::Display`)は、書いたパスそのものと、起点を名乗る明示の `use` の全部についてその取り込みのパスへ置き換えたパスとを候補にし、
//! 修飾が指しうるモジュールとその `use` の1段で探す。見つからなければ走査範囲に宣言が無いと答え、同名の宣言へ退避しない。明示のパスで決まるトレイトを同じ名前の別のトレイトと混ぜないためである。
//! 修飾の無い表記は、実装のモジュールの宣言と明示の `use` の全部と glob の取り込みの在り処を合わせて見る(cfg で切り替わる同名の候補を1つに決めないため。glob を候補にする条件は `module_index/name_location_search.rs`)。どれでも見つからなければ、prelude の名前か、glob の取り込み元がすべて走査範囲の外のクレート(`use std::fmt::*;`)なら
//! 走査範囲に宣言が無いと答え、それ以外は実装のクレートと glob の取り込み元のクレートの同名の宣言を保守的に見る。検査器がたどらない形で持ち込まれた名前を、黙って通さないためである。
//! glob の先の複数のモジュールに宣言があれば全部を見る。1段たどった先でさらに取り込みが続く(多段の再公開)なら、たどり切れなかった取り込みが指すクレートの同名の宣言を保守的に見る。
//! 実装のモジュールは位置のモジュール(ファイルのモジュール + 囲む `mod 名 { … }` の並び)であり、表記はそのモジュールに書いた `use` だけで解く。波括弧付きのモジュールは親の `use` を引き継がないためである。

use super::super::line_matching::{パスの修飾, パスの最後の名前};
use super::super::module_index::name_location::名前の在り処;
use super::super::module_index::name_location_search::名前の在り処の探索;
use super::super::module_index::モジュールの索引;
use super::super::module_path::モジュールパス;
use super::super::prelude_trait_names::取り込まずに書けるトレイトの名前か;
use super::super::read_implementation::読んだ実装;
use super::super::trait_declaration_index::{トレイトの宣言の索引, 見るトレイトの宣言};
use super::scan_range_exclusion::globの取り込み元がすべて走査範囲の外のクレートか;

/// 実装が書いたトレイトの宣言の在り処。
pub enum トレイトの宣言の在り処 {
    別名を通している,
    見る宣言(見るトレイトの宣言),
}

impl トレイトの宣言の在り処 {
    // 名前の在り処から作る。宣言したモジュールの宣言と、たどり切れなかった取り込みが指すクレートの同名の宣言を見る。見つからなければ、見つからないときのクレートの一覧の同名の宣言を見る。
    fn 名前の在り処から作る(在り処: 名前の在り処, 見つからないときのクレート一覧: Vec<モジュールパス>) -> Self {
        if 在り処.別名を通しているか {
            return Self::別名を通している;
        }
        let 同名の宣言を見るクレート一覧 = if 在り処.見つからないか() {
            見つからないときのクレート一覧
        } else {
            在り処.たどり切れなかったモジュール一覧.iter().map(モジュールパス::クレート).collect()
        };
        Self::見る宣言(見るトレイトの宣言 {
            モジュール一覧: 在り処.宣言したモジュール一覧,
            同名の宣言を見るクレート一覧,
        })
    }
}

/// 実装が書いたトレイトの宣言の在り処を問う相手。読んだ実装とトレイトの表記(`変更`・`crate::a::変更<u8>`)の組である。
pub struct トレイトの宣言の在り処の問い<'a> {
    pub 実装: &'a 読んだ実装<'a>,
    pub 表記: &'a str,
}

impl トレイトの宣言の在り処の問い<'_> {
    pub fn 在り処を答える(&self, 索引: &モジュールの索引, トレイトの索引: &トレイトの宣言の索引) -> トレイトの宣言の在り処 {
        let パス = self.表記.split('<').next().unwrap_or_default().trim().trim_start_matches("::");
        let 名前 = パスの最後の名前(パス);
        let 探索 = 名前の在り処の探索 {
            索引,
            名前,
            宣言しているか: |モジュール: &モジュールパス| トレイトの索引.宣言しているか(モジュール, 名前),
        };
        let 自分 = self.実装.位置のモジュール(索引);
        let 起点 = パス.split("::").next().unwrap_or_default().trim();
        if 起点 == パス {
            return self.修飾の無い名前から求める(&探索, &自分);
        }
        修飾のある表記から求める(&探索, パス, &自分)
    }

    // 修飾の無い名前の在り処。実装の位置のモジュールの宣言と、明示の取り込みの全部と、glob の取り込みの在り処を合わせる。
    // 宣言も明示の取り込みも無く glob の先にも見つからなければ、prelude の名前か glob の取り込み元がすべて走査範囲の外のクレートでない限り、実装のクレートと glob の取り込み元のクレートの同名の宣言を見る。
    fn 修飾の無い名前から求める<F: Fn(&モジュールパス) -> bool>(&self, 探索: &名前の在り処の探索<'_, F>, 自分: &モジュールパス) -> トレイトの宣言の在り処 {
        let 候補 = 探索.修飾の無い名前を取り込みから探す(自分);
        let 明示の取り込みが無いか = 候補.明示の取り込みごとの在り処.is_empty();
        let mut 在り処 = 名前の在り処::合わせる(候補.明示の取り込みごとの在り処.into_iter().chain(候補.globごとの在り処));
        在り処.別名を通しているか |= 候補.別名を通しているか;
        if 候補.自分が宣言しているか {
            在り処.宣言したモジュール一覧.push(自分.clone());
        }
        let 退避するか = 明示の取り込みが無いか && !取り込まずに書けるトレイトの名前か(探索.名前) && !globの取り込み元がすべて走査範囲の外のクレートか(探索.索引, 自分, self.実装.パス);
        let 退避のクレート一覧 = if 退避するか {
            let globのクレート一覧 = 探索.索引.取り込みの項目一覧(自分).iter().filter(|項目| 項目.全部を取り込むか()).map(|項目| 探索.索引.書かれたパスのクレート(自分, &項目.パス));
            std::iter::once(自分.クレート()).chain(globのクレート一覧).collect()
        } else {
            Vec::new()
        };
        トレイトの宣言の在り処::名前の在り処から作る(在り処, 退避のクレート一覧)
    }
}

// 自分(実装の位置のモジュール)に書かれた修飾のあるトレイトのパスの在り処。書いたパスそのものと、起点を名乗る明示の `use` の全部について、その取り込みのパスへ置き換えたパスとを候補にして探す。
fn 修飾のある表記から求める<F: Fn(&モジュールパス) -> bool>(探索: &名前の在り処の探索<'_, F>, パス: &str, 自分: &モジュールパス) -> トレイトの宣言の在り処 {
    let 起点 = パス.split("::").next().unwrap_or_default().trim();
    let 置き換えたパス一覧 = 探索
        .索引
        .取り込みの項目一覧(自分)
        .iter()
        .filter(|項目| !項目.全部を取り込むか() && 項目.名乗る名前() == 起点)
        .map(|項目| format!("{}{}", 項目.パス, パス.get(起点.len()..).unwrap_or_default()));
    let 候補一覧: Vec<モジュールパス> = std::iter::once(パス.to_string())
        .chain(置き換えたパス一覧)
        .flat_map(|候補のパス| 自分.書かれたパスが指しうるモジュール一覧(パスの修飾(&候補のパス).unwrap_or_default()))
        .collect();
    トレイトの宣言の在り処::名前の在り処から作る(探索.候補から探す(&候補一覧), Vec::new())
}
