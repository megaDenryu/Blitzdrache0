//! 実装が書いたトレイトの表記から、そのトレイトの宣言を索引のどこで見るかを求める工程。受け取るのは読んだ実装とトレイトの表記とモジュールの索引とトレイトの宣言の索引、返すのは宣言の在り処である。
//! トレイトの同一性は宣言のモジュールパス + 名前である(`trait_declaration_index.rs`)。表記は、実装の対象の型と同じ規則(`module_index/name_location_search.rs`)で宣言のモジュールへ結び付ける。
//! 修飾のある表記(`甲::変更`・`crate::甲::変更`・`super::甲::変更`・`self::甲::変更`・`std::fmt::Display`)は、起点を明示の `use` で取り込んでいればその取り込みのパスへ置き換えてから、
//! 修飾が指しうるモジュールとその `use` の1段で探す。見つからなければ走査範囲に宣言が無いと答え、同名の宣言へ退避しない。明示のパスで決まるトレイトを同じ名前の別のトレイトと混ぜないためである。
//! 修飾の無い表記は、実装のモジュールの宣言・明示の `use`・glob の取り込みの順に探す。どれでも見つからなければ、prelude の名前なら走査範囲に宣言が無いと答え、
//! それ以外は実装のクレートと glob の取り込み元のクレートの同名の宣言を保守的に見る。検査器がたどらない形で持ち込まれた名前を、黙って通さないためである。
//! glob の先の複数のモジュールに宣言があれば全部を見る。1段たどった先でさらに取り込みが続く(多段の再公開)なら、たどり切れなかった取り込みが指すクレートの同名の宣言を保守的に見る。
//! 波括弧付きのモジュールの中の実装は、ファイルのモジュールと位置のモジュール(囲む `mod` の並びを繋いだもの)の両方から求めた在り処を合わせる。`use` の索引がファイルの単位であり、どちらか一方では相対のパスを解き損ねうるためである。

use super::super::line_matching::{パスの修飾, パスの最後の名前};
use super::super::module_index::name_location_search::{修飾の無い名前の在り処, 名前の在り処, 名前の在り処の探索};
