//! 実装が書いたトレイトの宣言がどのクレートにありうるかを、取り込み元から決める工程。受け取るのは実装のモジュールパスとトレイトの表記とモジュールの索引、返すのは宣言のクレートの候補である。
//! トレイトの宣言の索引(`trait_declaration_index.rs`)は、候補のクレートの宣言を参照する。名前だけで引くと、別のクレートの無関係な同名の宣言が自己変更を与える関数を持つとき、偽の違反になるためである。
//! 決め方は次のとおりである。名前かパスの起点を明示の `use` で取り込んでいれば、その取り込み元のクレートである。取り込んでいないパスは、パスの起点のクレートである。取り込んでいない修飾の無い名前は、glob の取り込みも無ければ実装と同じクレートである。
//! glob の取り込みがあれば、実装と同じクレートと、glob の取り込み元のクレートと、glob が同じクレートを指すなら同じクレートの `use` がその名前か glob で取り込んでいるクレートを、すべて候補にする。
//! 候補のどのクレートにも宣言が無いときは、索引が同名の全宣言を参照する(従来の安全側)。再公開の連鎖で宣言が候補の外のクレートにある形を、黙って通さないためである。

use super::super::line_matching::パスの最後の名前;
use super::super::module_index::モジュールの索引;
use super::super::module_path::モジュールパス;
use super::super::trait_declaration_index::トレイトの宣言のクレートの候補;

/// 実装が書いたトレイトの宣言のクレートを問う相手。実装のモジュールパスとトレイトの表記(`変更`・`crate::a::変更<u8>`)の組である。
pub struct トレイトの宣言のクレートの問い<'a> {
    pub 自分: &'a モジュールパス,
    pub 表記: &'a str,
}

impl トレイトの宣言のクレートの問い<'_> {
    pub fn 候補を答える(&self, 索引: &モジュールの索引<'_>) -> トレイトの宣言のクレートの候補 {
        let パス = self.表記.split('<').next().unwrap_or_default().trim().trim_start_matches("::");
        let 名前 = パスの最後の名前(パス);
        let 起点 = パス.split("::").next().unwrap_or_default().trim();
        let 項目一覧 = 索引.取り込みの項目一覧(self.自分);
        if let Some(項目) = 項目一覧.iter().find(|項目| 項目.名乗る名前() == 起点) {
            return トレイトの宣言のクレートの候補(vec![索引.書かれたパスのクレート(self.自分, &項目.パス)]);
        }
        if パス != 名前 {
            return トレイトの宣言のクレートの候補(vec![索引.書かれたパスのクレート(self.自分, パス)]);
        }
        let 自分のクレート = self.自分.クレート();
        let glob一覧: Vec<モジュールパス> = 項目一覧.iter().filter(|項目| 項目.全部を取り込むか()).map(|項目| 索引.書かれたパスのクレート(self.自分, &項目.パス)).collect();
        let mut 候補 = vec![自分のクレート.clone()];
        if glob一覧.contains(&自分のクレート) {
            候補.extend(
                索引
                    .クレートの取り込みの組一覧(&自分のクレート)
                    .into_iter()
                    .filter(|(_, 項目)| 項目.全部を取り込むか() || 項目.元の名前() == 名前)
                    .map(|(モジュール, 項目)| 索引.書かれたパスのクレート(モジュール, &項目.パス)),
            );
        }
        候補.extend(glob一覧);
        トレイトの宣言のクレートの候補(候補)
    }
}
