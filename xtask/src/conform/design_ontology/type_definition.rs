//! 型の定義の探索。呼び出し連鎖の中の独立した工程であり、受け取るのは全ソースと型の在り処の問い(型の名前と、その名前を書いている行の位置)、
//! 返すのは定義ブロック(直前の属性の行を含む)とそのファイルのパスと定義の位置のモジュールか、見つからないか、同名の定義が複数あって一意に決まらないか、`as` の別名のため取り込み元を求められないかである。
//! 型の同一性は「定義の位置のモジュール + 型名」である。定義の位置のモジュールとは、定義のファイルから推定したモジュールパスの下へ、定義の行を囲む `mod 名 { … }` の名前を外側から繋いだものである(子のモジュール `type_definition/definition_candidate.rs`)。
//! 実装の位置のモジュールの直下に同名の定義があればそれを採り、無ければ実装の位置のモジュールの直下の `use` 行から取り込み元のモジュールパスを求めて、そのモジュールの直下の定義を採る(子のモジュール `type_definition/import_origin.rs`)。
//! 同じファイルでも、別の波括弧付きのモジュールの定義と関数の本体などの局所の定義は、実装が書いた型名の定義として採らない。Rust ではそれらは実装の位置から修飾か `use` 無しには名指せず、局所の定義はその本体の外から見えないためである。
//! そうした定義しか無く `use` も無ければ一意に決まらないと返し、黙って別の定義を採らない。実装が局所の位置にあり、同じファイルに同名の局所の定義があるときと、実装の位置のモジュールのマクロの呼び出しの中(`素通し! { … }`)に同名の定義があるときは、それらが名前を隠しうるため一意に決まらないと返す。
//! 明示した取り込み元を求められないときは、他のモジュールの同名定義を推測で採らない。型名を名乗る取り込みの取り込み元が複数ある(cfg で切り替わる取り込み)ときと、実装の位置のモジュールの直下の定義と型名を名乗る `use` が同時にあるときは、一意に決まらないと返す。

mod definition_candidate;
mod import_origin;

use std::path::{Path, PathBuf};

use super::module_path::モジュールパス;
use definition_candidate::同名の定義の候補;
use import_origin::{取り込み元の問い, 取り込み元を求めた結果};

/// ある型の定義がどこに在るかの問い。型の名前と、その名前を書いている行の位置の組である。
pub struct 型の在り処の問い<'a> {
    pub 型名: &'a str,
    pub 参照元のパス: &'a Path,
    pub 参照元の行番号: usize,
}

/// 型の定義の探索の結果。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 定義ブロックの結果 {
    見つかった { 定義: String, パス: PathBuf, モジュール: モジュールパス }, // モジュールは定義の位置のモジュールである
    見つからない,
    複数ある,
    別名のため取り込み元を求められない,
}

impl 定義ブロックの結果 {
    // 候補の一覧から1つだけ採る。1つも無ければ見つからない、2つ以上なら複数ある。
    fn 候補から1つ採る(mut 候補一覧: impl Iterator<Item = 同名の定義の候補>) -> Self {
        match (候補一覧.next(), 候補一覧.next()) {
            (Some(候補), None) => Self::見つかった {
                定義: 候補.定義,
                パス: 候補.パス,
                モジュール: 候補.位置.モジュール,
            },
            (Some(_), Some(_)) => Self::複数ある,
            (None, _) => Self::見つからない,
        }
    }
}

impl 型の在り処の問い<'_> {
    /// 走査したソースから、この問いが指す型の定義を探す。
    pub fn 型の定義を探す(&self, ソース一覧: &[(PathBuf, Vec<String>)]) -> 定義ブロックの結果 {
        let Some((_, 行一覧)) = ソース一覧.iter().find(|(パス, _)| パス == self.参照元のパス) else {
            return 定義ブロックの結果::見つからない;
        };
        let 字句位置一覧 = モジュールパス::ファイルのパスから求める(self.参照元のパス).行ごとの字句位置一覧(行一覧);
        let Some(実装の位置) = 字句位置一覧.get(self.参照元の行番号.saturating_sub(1)) else {
            return 定義ブロックの結果::見つからない;
        };
        let (同じファイルの候補一覧, 他のファイルの候補一覧): (Vec<同名の定義の候補>, Vec<同名の定義の候補>) = 同名の定義の候補::全ソースから集める(ソース一覧, self.型名).into_iter().partition(|候補| 候補.パス == self.参照元のパス);
        let (直下の候補一覧, 採らない候補一覧): (Vec<同名の定義の候補>, Vec<同名の定義の候補>) = 同じファイルの候補一覧.into_iter().partition(|候補| 候補.モジュールの直下にあるか(&実装の位置.モジュール));
        if 採らない候補一覧.iter().any(|候補| 候補.実装の名前を隠しうるか(実装の位置)) {
            return 定義ブロックの結果::複数ある;
        }
        let 取り込み元 = (取り込み元の問い { 型名: self.型名, 実装の位置 }).行一覧から取り込み元を求める(行一覧, &字句位置一覧);
        if !直下の候補一覧.is_empty() {
            return match 取り込み元 {
                取り込み元を求めた結果::取り込んでいない => 定義ブロックの結果::候補から1つ採る(直下の候補一覧.into_iter()),
                取り込み元を求めた結果::取り込んでいる { .. } | 取り込み元を求めた結果::取り込み元が複数ある | 取り込み元を求めた結果::別名のため取り込み元を求められない => {
                    定義ブロックの結果::複数ある
                }
            };
        }
        match 取り込み元 {
            取り込み元を求めた結果::別名のため取り込み元を求められない => 定義ブロックの結果::別名のため取り込み元を求められない,
            取り込み元を求めた結果::取り込んでいる {
                モジュールパス: 定義のモジュール
            } => {
                let 全部の候補 = 採らない候補一覧.into_iter().chain(他のファイルの候補一覧);
                定義ブロックの結果::候補から1つ採る(全部の候補.filter(|候補| 候補.モジュールの直下にあるか(&定義のモジュール)))
            }
            取り込み元を求めた結果::取り込み元が複数ある => 定義ブロックの結果::複数ある,
            取り込み元を求めた結果::取り込んでいない if !採らない候補一覧.is_empty() => 定義ブロックの結果::複数ある,
            取り込み元を求めた結果::取り込んでいない => 定義ブロックの結果::見つからない,
        }
    }
}
