//! 型の定義の探索。呼び出し連鎖の中の独立した工程であり、受け取るのは全ソースと `impl トレイト for 型` の1件、
//! 返すのは定義ブロック(直前の属性の行を含む)とそのファイルのパスか、見つからないか、同名の定義が複数のファイルにあって一意に決まらないかである。
//! 実装と同じファイルの定義を優先し、無ければ全体で1つだけのものを採る。2つ以上なら黙って1つを選ばず、複数あると返す。

use std::path::PathBuf;

use super::line_matching::{波括弧が閉じる行, 語として現れるか};
use super::syntax_checker::トレイト実装型;
use super::syntax_patterns::構文パターン;

/// 型の定義の探索の結果。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 定義ブロックの結果 {
    見つかった { 定義: String, パス: PathBuf },
    見つからない,
    複数ある,
}

pub fn 型の定義を探す(ソース一覧: &[(PathBuf, Vec<String>)], 型: &トレイト実装型) -> 定義ブロックの結果 {
    let シグネチャ = 構文パターン::型定義のシグネチャ(&型.型名);
    let mut 候補一覧 = Vec::new();
    for (パス, 行一覧) in ソース一覧 {
        let Some(開始) = 行一覧.iter().position(|行| シグネチャ.iter().any(|宣言| 語として現れるか(行, 宣言))) else {
            continue;
        };
        if *パス == 型.パス {
            return 定義ブロックの結果::見つかった {
                定義: 定義ブロック(行一覧, 開始),
                パス: パス.clone(),
            };
        }
        候補一覧.push((定義ブロック(行一覧, 開始), パス.clone()));
    }
    match 候補一覧.len() {
        0 => 定義ブロックの結果::見つからない,
        1 => {
            let (定義, パス) = 候補一覧.remove(0);
            定義ブロックの結果::見つかった { 定義, パス }
        }
        _ => 定義ブロックの結果::複数ある,
    }
}

// 開始の行の定義を、直前に続く属性の行と空行を含めて1つの文字列にする。
fn 定義ブロック(行一覧: &[String], 開始: usize) -> String {
    let 終了 = 波括弧が閉じる行(行一覧, 開始);
    let 属性開始 = (0..開始).rev().take_while(|添字| 行一覧[*添字].trim().is_empty() || 行一覧[*添字].trim().starts_with("#[")).last().unwrap_or(開始);
    行一覧[属性開始..=終了].join("\n")
}
