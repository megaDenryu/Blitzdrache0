//! 型の定義の探索。呼び出し連鎖の中の独立した工程であり、受け取るのは全ソースと `impl トレイト for 型` の1件、
//! 返すのは定義ブロック(直前の属性の行を含む)とそのファイルのパスか、見つからないか、同名の定義が複数あって一意に決まらないか、`as` の別名のため取り込み元を求められないかである。
//! 同じファイルに同名の定義が2つ以上あるとき(波括弧付きのモジュール `mod 名 { ... }` で分けた場合)も一意に決まらないと返す。
//! 型の同一性は「定義のモジュールパス + 型名」である。実装と同じファイルの定義を採り、無ければ実装のファイルの `use` 行から取り込み元のモジュールパスを求めて、そのモジュールパスの定義を採る。
//! `use` が無ければ全体で1つだけの同名の定義を採る(`super::` の修飾や glob の取り込みを黙って落とさないため)。2つ以上なら黙って1つを選ばず、複数あると返す。

use std::path::{Path, PathBuf};

use super::line_matching::{クレート名, 波括弧が閉じる行, 語として現れるか};
use super::module_path::モジュールパス;
use super::syntax_patterns;
use super::trait_implementation::トレイト実装型;
use super::use_resolution::{取り込み元の問い, 取り込み元を求めた結果};

/// 型の定義の探索の結果。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 定義ブロックの結果 {
    見つかった { 定義: String, パス: PathBuf },
    見つからない,
    複数ある,
    別名のため取り込み元を求められない,
}

pub fn 型の定義を探す(ソース一覧: &[(PathBuf, Vec<String>)], 型: &トレイト実装型) -> 定義ブロックの結果 {
    let mut 候補一覧 = 同名の定義の候補一覧(ソース一覧, &型.型名);
    let 同じファイルの位置一覧: Vec<usize> = 候補一覧.iter().enumerate().filter(|(_, (_, パス))| *パス == 型.パス).map(|(位置, _)| 位置).collect();
    match 同じファイルの位置一覧.as_slice() {
        [] => {}
        [位置] => {
            let (定義, パス) = 候補一覧.remove(*位置);
            return 定義ブロックの結果::見つかった { 定義, パス };
        }
        _ => return 定義ブロックの結果::複数ある,
    }
    let Some((_, 行一覧)) = ソース一覧.iter().find(|(パス, _)| *パス == 型.パス) else {
        return 定義ブロックの結果::見つからない;
    };
    let 問い = 取り込み元の問い {
        自分のモジュールパス: &モジュールパス::ファイルのパスから求める(&型.パス),
        型名: &型.型名,
    };
    match 問い.行一覧から取り込み元を求める(行一覧) {
        取り込み元を求めた結果::別名のため取り込み元を求められない => 定義ブロックの結果::別名のため取り込み元を求められない,
        取り込み元を求めた結果::取り込んでいる {
            モジュールパス: 定義のモジュール
        } => {
            let mut 一致一覧 = 候補一覧.into_iter().filter(|(_, パス)| モジュールパス::ファイルのパスから求める(パス) == 定義のモジュール);
            match (一致一覧.next(), 一致一覧.next()) {
                (Some((定義, パス)), None) => 定義ブロックの結果::見つかった { 定義, パス },
                (Some(_), Some(_)) => 定義ブロックの結果::複数ある,
                (None, _) => 定義ブロックの結果::見つからない,
            }
        }
        取り込み元を求めた結果::取り込んでいない => match 候補一覧.len() {
            0 => 定義ブロックの結果::見つからない,
            1 => {
                let (定義, パス) = 候補一覧.remove(0);
                定義ブロックの結果::見つかった { 定義, パス }
            }
            _ => 定義ブロックの結果::複数ある,
        },
    }
}

/// 固有の `impl 型名 {` を持つかもしれないファイル。どの定義に属するかを答える。
pub struct 固有implのファイル<'a> {
    pub パス: &'a Path,
    pub 行一覧: &'a [String],
}

impl 固有implのファイル<'_> {
    /// このファイルの `impl 型名 {` が、そのパスの定義に属するか。同じファイルか、`use` 行から求めた取り込み元がその定義のモジュールパスを指すか、
    /// `use` が無く同じクレートの中で同名の定義が全体で1つだけか、のいずれかである。`as` の別名は属さない。
    pub fn 定義を指すか(&self, ソース一覧: &[(PathBuf, Vec<String>)], 型名: &str, 定義のパス: &Path) -> bool {
        if self.パス == 定義のパス {
            return true;
        }
        let 問い = 取り込み元の問い {
            自分のモジュールパス: &モジュールパス::ファイルのパスから求める(self.パス),
            型名,
        };
        match 問い.行一覧から取り込み元を求める(self.行一覧) {
            取り込み元を求めた結果::取り込んでいる { モジュールパス: 取り込み元 } => 取り込み元 == モジュールパス::ファイルのパスから求める(定義のパス),
            取り込み元を求めた結果::別名のため取り込み元を求められない => false,
            取り込み元を求めた結果::取り込んでいない => クレート名(self.パス) == クレート名(定義のパス) && 同名の定義の候補一覧(ソース一覧, 型名).len() == 1,
        }
    }
}

// 全ソースから同名の `struct`/`enum` の定義を全部集める。同じファイルに2つ以上あればその分だけ並び、呼び出し側が一意に決まらないと判定する(黙って最初の1つを採らない)。
fn 同名の定義の候補一覧(ソース一覧: &[(PathBuf, Vec<String>)], 型名: &str) -> Vec<(String, PathBuf)> {
    let シグネチャ = syntax_patterns::型定義のシグネチャ(型名);
    ソース一覧
        .iter()
        .flat_map(|(パス, 行一覧)| {
            let 開始一覧 = 行一覧.iter().enumerate().filter(|(_, 行)| シグネチャ.iter().any(|宣言| 語として現れるか(行, 宣言))).map(|(開始, _)| 開始);
            開始一覧.map(|開始| (定義ブロック(行一覧, 開始), パス.clone())).collect::<Vec<_>>()
        })
        .collect()
}

// 開始の行の定義を、直前に続く属性の行と空行を含めて1つの文字列にする。
fn 定義ブロック(行一覧: &[String], 開始: usize) -> String {
    let 終了 = 波括弧が閉じる行(行一覧, 開始);
    let 属性開始 = (0..開始).rev().take_while(|添字| 行一覧[*添字].trim().is_empty() || 行一覧[*添字].trim().starts_with("#[")).last().unwrap_or(開始);
    行一覧[属性開始..=終了].join("\n")
}
