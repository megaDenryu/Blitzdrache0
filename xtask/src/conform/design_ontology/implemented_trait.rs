//! 実装が書いたトレイト1件(トレイトを書いた位置の表記と実装の在り処の組)と、その宣言から自己変更の根拠を求める工程。受け取るのはトレイトの宣言の索引と名前の言い換えの辺の一覧と自己変更を問う対象、返すのは根拠である。
//! 宣言は、表記のパスの最後の要素の名前の閉包で引く。パスを解いて宣言を1つに決める形をやめたのは、`use`・glob・再公開・別名・cfg・局所の項目・波括弧付きのモジュール・マクロの呼び出しの中を解く解き方に、名前を取りこぼす穴が繰り返し見つかったためである。
//! 走査範囲にその名前の宣言が1件も無ければ、そのトレイトは走査範囲の外(std・core・alloc・外部の依存クレート)のものである。検査器はその既定の関数を読めず、検査しない。
//! 走査範囲の外のトレイトを検査しないことの論証は `_doc/設計/設計オントロジー.md` 2.5.3 が持つ。宣言の本体の直下でマクロを呼ぶトレイトは、生える既定の関数を読めないため黙って通さず根拠にする。

use std::path::{Path, PathBuf};

use super::function_signature::自己変更を問う対象;
use super::line_matching::パスの最後の名前;
use super::marker_name_closure::名前の言い換えの辺一覧;
use super::self_modification_evidence::自己変更の根拠;
use super::trait_declaration_index::{トレイトの宣言の索引, トレイトの宣言を参照した結果};

/// 実装が書いたトレイト。トレイトを書いた位置の表記(`変更`・`crate::a::変更<u8>`)と、その実装の在り処の組である。
pub struct 実装したトレイト<'a> {
    pub 表記: &'a str,
    pub パス: &'a Path,
    pub 行番号: usize,
}

impl 実装したトレイト<'_> {
    /// 実装したトレイトの宣言の関数が対象へ自己変更を与えるなら、その根拠。宣言を完全に読めないトレイトも根拠にする。
    pub fn 自己変更の根拠(&self, 索引: &トレイトの宣言の索引, 辺一覧: &名前の言い換えの辺一覧, 対象: &自己変更を問う対象) -> Option<自己変更の根拠> {
        let 名前の集合 = 辺一覧.閉包(パスの最後の名前(self.表記));
        let (パス, 行番号): (PathBuf, usize) = (self.パス.to_path_buf(), self.行番号);
        match 索引.宣言を参照する(&名前の集合, 対象) {
            トレイトの宣言を参照した結果::宣言が無い | トレイトの宣言を参照した結果::自己変更を与えない => None,
            トレイトの宣言を参照した結果::自己変更を与える {
                トレイト名, 関数名, 同名の宣言の件数
            } => Some(自己変更の根拠::トレイトの宣言の関数 {
                パス,
                行番号,
                対象の名前: 対象.型名.to_string(),
                トレイト名,
                関数名,
                同名の宣言の件数,
            }),
            トレイトの宣言を参照した結果::宣言を完全に読めない { トレイト名, マクロ名 } => Some(自己変更の根拠::宣言を完全に読めないトレイト {
                パス, 行番号, トレイト名, マクロ名
            }),
        }
    }
}
