//! 実装が書いたトレイト1件(読んだ実装と、トレイトを書いた位置の表記の組)と、その宣言から自己変更の根拠を求める工程。受け取るのはトレイトの宣言の索引とモジュールの索引と自己変更を問う対象、返すのは根拠である。
//! 宣言の関数が対象へ自己変更を与えるなら、その関数を根拠にする。宣言の本体の直下でマクロを呼ぶトレイトは、生える関数を読めないため根拠にする。
//! 宣言は、トレイトの表記を宣言のモジュールへ結び付けた在り処(子のモジュール `implemented_trait/declaring_module.rs`)で索引を引く。
//! `use … as` の別名(このファイルと、明示の取り込みか glob の取り込みの取り込み元の再公開を1段たどる)を通したトレイトは宣言を引けないため根拠にする。
//! 局所の位置の実装(関数の本体の中の `impl`)が書いたトレイトの名前(修飾があればその起点)を、そのファイルの局所の `use` か項目が隠しうるなら、局所の宣言と取り込みは索引に無く宣言を引けないため根拠にする。
//! 実装の位置のモジュールで波括弧を使って呼んだマクロの本体(マクロの呼び出しの中)の `use` か項目がそのトレイトの名前(修飾があればその起点)を隠しうるなら、同じく宣言を引けないため根拠にする。
//! この2つは、prelude の名前・依存クレートの名前・走査範囲の外のトレイトとして通す判定より先に問う。そこへ宣言されたトレイトが名前をすり替えうるためである。
//! 索引に宣言が無いトレイトを検査しなくてよいかは、子のモジュール `implemented_trait/scan_range_exclusion.rs` が判定する。

mod declaring_module;
mod scan_range_exclusion;

use super::function_signature::自己変更を問う対象;
use super::line_matching::{パスの修飾, パスの最後の名前};
use super::module_index::モジュールの索引;
use super::read_implementation::読んだ実装;
use super::self_modification_evidence::自己変更の根拠;
use super::trait_declaration_index::{トレイトの宣言の索引, トレイトの宣言を参照した結果};
use declaring_module::{トレイトの宣言の在り処, トレイトの宣言の在り処の問い};

/// 実装が書いたトレイト。読んだ実装と、トレイトを書いた位置の表記(`変更`・`crate::a::変更<u8>`)の組である。
pub struct 実装したトレイト<'a> {
    pub 実装: &'a 読んだ実装<'a>,
    pub 表記: &'a str,
}

impl 実装したトレイト<'_> {
    /// 実装したトレイトの宣言の関数が対象へ自己変更を与えるなら、その根拠。別名を通したトレイトと、宣言を読めないトレイトも根拠にする。
    pub fn 自己変更の根拠(&self, トレイトの索引: &トレイトの宣言の索引, モジュールの索引: &モジュールの索引, 対象: &自己変更を問う対象) -> Option<自己変更の根拠> {
        let 名前 = パスの最後の名前(self.表記);
        let (パス, 行番号) = (self.実装.パス.to_path_buf(), self.実装.行番号);
        let 別名の根拠 = || {
            Some(自己変更の根拠::別名で取り込んだトレイト {
                パス: パス.clone(),
                行番号,
                別名: 名前.to_string(),
            })
        };
        if !self.実装.別名の元の名前一覧(モジュールの索引, パスの修飾(self.表記), 名前).is_empty() {
            return 別名の根拠();
        }
        if self.実装.局所の名前が隠しうるか(モジュールの索引, self.起点()) {
            return Some(自己変更の根拠::局所の名前が隠しうるトレイト {
                パス: パス.clone(),
                行番号,
                トレイトの表記: self.表記.to_string(),
            });
        }
        if self.実装.マクロの呼び出しの中の名前が隠しうるか(モジュールの索引, self.起点()) {
            return Some(自己変更の根拠::マクロの呼び出しの中の名前が隠しうるトレイト {
                パス: パス.clone(),
                行番号,
                トレイトの表記: self.表記.to_string(),
            });
        }
        let 見る = match (トレイトの宣言の在り処の問い { 実装: self.実装, 表記: self.表記 }).在り処を答える(モジュールの索引, トレイトの索引) {
            トレイトの宣言の在り処::別名を通している => return 別名の根拠(),
            トレイトの宣言の在り処::見る宣言(見る) => 見る,
        };
        match トレイトの索引.宣言を参照する(&見る, 名前, 対象) {
            トレイトの宣言を参照した結果::自己変更を与える { 関数名 } => Some(自己変更の根拠::トレイトの宣言の関数 {
                トレイト名: 名前.to_string(), 関数名
            }),
            トレイトの宣言を参照した結果::自己変更を与えない => None,
            トレイトの宣言を参照した結果::宣言を完全に読めない { マクロ名 } => Some(自己変更の根拠::宣言を完全に読めないトレイト {
                パス,
                行番号,
                トレイト名: 名前.to_string(),
                マクロ名,
            }),
            トレイトの宣言を参照した結果::宣言が無い if self.走査範囲の外か(モジュールの索引) => None,
            トレイトの宣言を参照した結果::宣言が無い => Some(自己変更の根拠::宣言を読めないトレイト {
                パス,
                行番号,
                トレイトの表記: self.表記.to_string(),
            }),
        }
    }

    // 型引数と先頭の `::` を除いたトレイトのパス(`crate::a::変更`)。
    fn パス(&self) -> &str {
        self.表記.split('<').next().unwrap_or_default().trim().trim_start_matches("::")
    }

    // トレイトのパスの起点(`crate::a::変更` なら `crate`、修飾が無ければ名前そのもの)。
    fn 起点(&self) -> &str {
        self.パス().split("::").next().unwrap_or_default().trim()
    }
}
