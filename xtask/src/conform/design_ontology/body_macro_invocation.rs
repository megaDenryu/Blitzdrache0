//! 実装の本体の直下(波括弧の深さ1)にあるマクロの呼び出し(`名前!(...)`・`名前!{...}`・`名前![...]`・`include!(...)`)を探す純粋な関数。
//! 本体の直下のマクロは関数を生やせるが、検査器はマクロを展開できず、生えた関数の署名を読めない。そのため見つけたら黙って通さず、自己変更の根拠にする。
//! 関数の本体の中のマクロ(`println!` 等)は深さが2以上であるため拾わない。`!=` と否定の `!(...)` は、`!` の直前が識別子でないか直後が括弧でないため拾わない。

use super::line_matching::先頭の識別子;

/// 本体(開く `{` から始まる文字列)の直下で最初に呼んだマクロの名前(パスで書いたならパスごと)。無ければ無い。
pub fn 本体の直下のマクロの呼び出し(本体: &str) -> Option<String> {
    let mut 深さ = 0usize;
    for (位置, 文字) in 本体.char_indices() {
        match 文字 {
            '{' => 深さ += 1,
            '}' => {
                深さ = 深さ.saturating_sub(1);
                if 深さ == 0 {
                    return None;
                }
            }
            '!' if 深さ == 1 && 本体[位置 + '!'.len_utf8()..].trim_start().starts_with(['(', '[', '{']) => {
                let 名前 = 直前のパス(&本体[..位置]);
                if !名前.is_empty() {
                    return Some(名前.to_string());
                }
            }
            _ => {}
        }
    }
    None
}

// 表記の末尾に続く、識別子と `::` の並び(`a::b` の形のパス)。
fn 直前のパス(前: &str) -> &str {
    let 始まり = 前.char_indices().rev().take_while(|&(_, 文字)| 文字.is_alphanumeric() || 文字 == '_' || 文字 == ':').last().map_or(前.len(), |(位置, _)| 位置);
    let パス = &前[始まり..];
    if 先頭の識別子(パス.trim_start_matches(':')).is_empty() { "" } else { パス }
}
