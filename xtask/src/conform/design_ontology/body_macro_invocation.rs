//! 実装かトレイトの宣言の本体の直下(波括弧の深さ1)で、項目の位置にあるマクロの呼び出し(`名前!(...)`・`名前!{...}`・`名前![...]`・`include!(...)`)を探す純粋な関数。
//! 本体の直下の項目の位置のマクロは関数を生やせるが、検査器はマクロを展開できず、生えた関数の署名を読めない。そのため見つけたら黙って通さず、自己変更の根拠にする。
//! 項目の位置とは、本体の直下の直前の区切り(`;`・`{`・`}`)からマクロの名前までが空白と閉じた属性(外側の `#[..]` と内側の `#![..]`)だけである位置のことである。
//! 式の位置のマクロ(`const X: bool = matches!(..);`・`#[doc = include_str!("..")] fn f(&self);`)は項目を生やさないため拾わない。
//! 関数の本体の中のマクロ(`println!` 等)は深さが2以上であるため拾わない。`!=` と否定の `!(...)` は、`!` の直前が識別子でないか直後が括弧でないため拾わない。

use super::declaration_prefix::先頭の属性を読み飛ばす;
use super::identifier_boundary::識別子の文字か;
use super::line_matching::先頭の識別子;

/// 本体(開く `{` から始まる文字列)の直下の項目の位置で最初に呼んだマクロの名前(パスで書いたならパスごと)。無ければ無い。
pub fn 本体の直下のマクロの呼び出し(本体: &str) -> Option<String> {
    let mut 深さ = 0usize;
    let mut 区切りの後ろ = 0usize; // 本体の直下の直前の区切りの次の位置
    for (位置, 文字) in 本体.char_indices() {
        let 次の位置 = 位置 + 文字.len_utf8();
        match 文字 {
            '{' => {
                深さ += 1;
                if 深さ == 1 {
                    区切りの後ろ = 次の位置;
                }
            }
            '}' => {
                深さ = 深さ.saturating_sub(1);
                match 深さ {
                    0 => return None,
                    1 => 区切りの後ろ = 次の位置,
                    _ => {}
                }
            }
            ';' if 深さ == 1 => 区切りの後ろ = 次の位置,
            '!' if 深さ == 1 && 本体[次の位置..].trim_start().starts_with(['(', '[', '{']) => {
                let 名前 = 直前のパス(&本体[..位置]);
                let 名前の前 = 本体.get(区切りの後ろ..位置.saturating_sub(名前.len())).unwrap_or_default();
                if !名前.is_empty() && 先頭の属性を読み飛ばす(名前の前).is_empty() {
                    return Some(名前.to_string());
                }
            }
            _ => {}
        }
    }
    None
}

// 表記の末尾に続く、識別子と `::` の並び(`a::b` の形のパス)。
fn 直前のパス(前: &str) -> &str {
    let 始まり = 前.char_indices().rev().take_while(|&(_, 文字)| 識別子の文字か(文字) || 文字 == ':').last().map_or(前.len(), |(位置, _)| 位置);
    let パス = &前[始まり..];
    if 先頭の識別子(パス.trim_start_matches(':')).is_empty() { "" } else { パス }
}
