//! 自己変更を問う相手と、関数の署名がその相手へ自己変更を与えるかの問い。受け取るのは関数の署名、返すのは真偽である。
//! 与えると答えるのは、実装が可変参照か可変の借用を対象にするか、見出しの境界の可変の借用が `Self` を指すか、名前が境界に当たったときと、受け手か引数が自分の型への可変参照であるときと、関数の署名の境界の可変の借用を与えるトレイトの型引数が `Self` か型名を指すとき(`fn 変える(mut 相手: impl DerefMut<Target = Self>)`)である。

use super::super::self_modification_evidence::名前が当たった場所;
use super::関数の署名;

/// 自己変更を問う相手。実装の対象の型の名前(全称の実装なら型引数の名前、マクロの中ならメタ変数)と、その実装が可変参照を対象にするかと、名前が見出しのどこに当たったかの組である。
pub struct 自己変更を問う対象<'a> {
    pub 型名: &'a str,
    pub 可変参照を対象にするか: bool, // 対象の表記に可変参照か可変の借用を与えるトレイトが現れるか、見出しの境界の可変の借用を与えるトレイトの型引数が `Self` を指すか、名前が境界に当たったとき真。真なら値で受ける `self` の関数も自己変更を与える
    pub 当たった場所: 名前が当たった場所,
}

impl<'a> 自己変更を問う対象<'a> {
    /// 対象の型を決められない実装(全称の実装とマクロの本体の中の実装と関数)の自分の型について問う相手。
    pub fn 決められない対象の型について(型名: &'a str, 可変参照を対象にするか: bool) -> Self {
        Self {
            型名,
            可変参照を対象にするか,
            当たった場所: 名前が当たった場所::決められない対象の型,
        }
    }

    /// その関数が対象の型へ自己変更を与えるか。可変参照を対象にする実装の関数は、受け手の形によらず与える。
    pub fn 自己変更を与えるか(&self, 関数: &関数の署名) -> bool {
        self.可変参照を対象にするか || 関数.自分の型への可変参照を持つか(self.型名) || 関数.境界.可変の借用で自分の型を指すか(self.型名)
    }
}
