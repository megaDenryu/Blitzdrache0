//! 1つのファイルの中で読んだ `impl` の1件。所在(ファイルのパスとコードだけの行の一覧と見出しの行番号)と見出しを持つ。
//! その所在から答えられる問いのうち、実装の位置のモジュールと、書いた名前が `use` の別名を通しているかと、局所の位置の実装が書いた名前を局所の `use` と項目が隠しうるかをここで答える。
//! 対象の型を定義へ結び付ける問いは `implementation_binding.rs`、トレイトが走査範囲の外かの問いは `implemented_trait.rs` が答える。
//! 関数の本体などの局所の位置に書いた実装も従来どおり読む。その名前はモジュールの直下の `use` と宣言だけで解くが、局所の `use` と項目は索引に無いため、
//! それらがその名前を隠しうるときは、呼び出し側がその実装を結び付けられない実装として違反の側へ倒す(`module_index/file_lexical_position.rs`)。
//! 実装の位置のモジュールのマクロの呼び出しの中(`素通し! { … }`)の `use` と項目も索引に無いため、それらが名前を隠しうるかも同じくここで答え、呼び出し側が違反の側へ倒す(どの位置の実装でも問う)。

use std::path::Path;

use super::impl_header::実装の見出し;
use super::module_index::モジュールの索引;
use super::module_path::モジュールパス;
use super::use_resolution::取り込みの項目;

pub struct 読んだ実装<'a> {
    pub パス: &'a Path,
    pub 行一覧: &'a [String],
    pub 行番号: usize, // 見出しの行の1始まりの番号。違反の報告がこの行を指す
    pub 見出し: 実装の見出し,
}

impl 読んだ実装<'_> {
    /// ファイルから推定したモジュールパスの下へ、見出しの行を囲む波括弧付きのモジュール(`mod 名 { … }`)の並びを繋いだ、実装の位置のモジュールパス。
    /// 実装が書いた名前は、このモジュールに書いた `use` だけで解く(波括弧付きのモジュールは親の `use` を引き継がない)。
    pub fn 位置のモジュール(&self, 索引: &モジュールの索引) -> モジュールパス {
        match 索引.ファイルの字句位置(self.パス).and_then(|字句位置| 字句位置.行の字句位置(self.見出しの添字())) {
            Some(位置) => 位置.モジュール.clone(),
            None => モジュールパス::ファイルのパスから求める(self.パス),
        }
    }

    /// 実装が局所の位置にあり、そのファイルの局所の `use` か項目が、書いた名前(修飾があればその起点)を隠しうるか。
    pub fn 局所の名前が隠しうるか(&self, 索引: &モジュールの索引, 名前: &str) -> bool {
        索引.ファイルの字句位置(self.パス).is_some_and(|字句位置| 字句位置.局所の名前が隠しうるか(self.見出しの添字(), 名前))
    }

    /// 実装が局所の位置にあり、そのファイルの局所の `use … as` か `type` の別名が、書いた名前で型名を指しうるか。
    pub fn 局所の別名が型名を指しうるか(&self, 索引: &モジュールの索引, 名前: &str, 型名: &str) -> bool {
        索引.ファイルの字句位置(self.パス).is_some_and(|字句位置| 字句位置.局所の別名が型名を指しうるか(self.見出しの添字(), 名前, 型名))
    }

    /// 実装の位置のモジュールのマクロの呼び出しの中の項目か `use` が、書いた名前(修飾があればその起点)を隠しうるか。
    pub fn マクロの呼び出しの中の名前が隠しうるか(&self, 索引: &モジュールの索引, 名前: &str) -> bool {
        索引.マクロの呼び出しの中の名前(&self.位置のモジュール(索引)).is_some_and(|控え| 控え.名前を隠しうるか(名前))
    }

    /// 実装の位置のモジュールのマクロの呼び出しの中の `use … as` か `type` の別名が、書いた名前で型名を指しうるか。
    pub fn マクロの呼び出しの中の別名が型名を指しうるか(&self, 索引: &モジュールの索引, 名前: &str, 型名: &str) -> bool {
        索引.マクロの呼び出しの中の名前(&self.位置のモジュール(索引)).is_some_and(|控え| 控え.別名が型名を指しうるか(名前, 型名))
    }

    fn 見出しの添字(&self) -> usize {
        self.行番号.saturating_sub(1)
    }

    /// 書いた名前(修飾があれば `修飾::名前`)が `use 元 as 名前` の別名を通しうるなら、その元のパスの最後の名前の全部(cfg で切り替わる別名は複数ありうる)。通していなければ空である。
    /// 実装の位置のモジュールの取り込みと、取り込み元のモジュール(修飾があれば修飾が指しうるモジュール、無ければ明示の取り込みの全部の取り込み元と、明示の取り込みに隠されない glob の取り込みの取り込み元)の取り込みを1段たどる。
    /// 再公開の `pub use … as` もこれで読む。
    pub fn 別名の元の名前一覧<'b>(&self, 索引: &'b モジュールの索引, 修飾: Option<&str>, 名前: &str) -> Vec<&'b str> {
        let 自分 = self.位置のモジュール(索引);
        let mut 元の名前一覧 = Vec::new();
        let 取り込み元一覧: Vec<&str> = match 修飾 {
            Some(修飾) => vec![修飾],
            None => {
                元の名前一覧.extend(索引.別名の元の名前一覧(&自分, 名前));
                let 項目一覧 = 索引.取り込みの項目一覧(&自分);
                let 明示の取り込み元一覧: Vec<&str> = 項目一覧.iter().filter(|項目| 項目.別名.is_none() && 項目.元の名前() == 名前).map(取り込みの項目::親のパス).collect();
                let globが隠されているか = !明示の取り込み元一覧.is_empty() && !索引.条件付きで束縛しているか(&自分, 名前);
                let glob一覧 = 項目一覧.iter().filter(|項目| !globが隠されているか && 項目.全部を取り込むか()).map(取り込みの項目::親のパス);
                明示の取り込み元一覧.into_iter().chain(glob一覧).collect()
            }
        };
        for モジュール in 取り込み元一覧.iter().flat_map(|取り込み元| 自分.書かれたパスが指しうるモジュール一覧(取り込み元)) {
            元の名前一覧.extend(索引.別名の元の名前一覧(&モジュール, 名前));
        }
        元の名前一覧
    }
}
