//! 1つのファイルの中で読んだ `impl` の1件。所在(ファイルのパスとコードだけの行の一覧)と見出しを持ち、対象の型の表記がある定義を指すかを自分で答える。

use std::path::Path;

use super::impl_header::実装の見出し;
use super::impl_syntax::実装の対象の型;
use super::module_path::モジュールパス;
use super::type_definition::固有implのファイル;

pub struct 読んだ実装<'a> {
    pub パス: &'a Path,
    pub 行一覧: &'a [String],
    pub 見出し: 実装の見出し,
}

impl 読んだ実装<'_> {
    /// 対象の型の表記が、そのパスのファイルにある定義を指すか。名前が一致していることは呼び出し側が確かめる。
    /// パスの修飾があれば、それをこのファイルのモジュールから見た絶対のパスと相対のパスの両方に読み、どちらかが定義のモジュールパスと一致すれば指すとみなす。
    /// 修飾が無ければ、このファイルが定義のファイルか、`use` で定義のモジュールから型名を取り込んだファイルであるときだけ指す(別のモジュールの同名の型を混ぜない)。
    pub fn 定義を指すか(&self, 対象: &実装の対象の型, 定義のパス: &Path) -> bool {
        let Some(修飾) = 対象.パスの修飾() else {
            return (固有implのファイル {
                パス: self.パス, 行一覧: self.行一覧
            })
            .定義を指すか(対象.名前(), 定義のパス);
        };
        let 定義のモジュール = モジュールパス::ファイルのパスから求める(定義のパス);
        let 自分のモジュール = モジュールパス::ファイルのパスから求める(self.パス);
        let 修飾の区切り一覧: Vec<&str> = 修飾.split("::").map(str::trim).collect();
        自分のモジュール.書かれたパスを絶対にする(修飾) == 定義のモジュール || 自分のモジュール.下へ繋ぐ(&修飾の区切り一覧) == 定義のモジュール
    }
}
