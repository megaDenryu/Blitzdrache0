//! 設計解釈マーカーを実装した構造体の名前付きのフィールドを行ごとに読み、各フィールドの型が `Mコマンド` を名乗る型かを判定する工程。
//! `M命令の組` の検査(フィールドがどれもコマンドであること。`命令の組の検査.rs`)と、`MParameter` の検査(フィールドがどれもコマンドなら命令の組を名乗るべきであること。
//! `コマンドだけを並べた引数オブジェクトの検査.rs`)が共に使う。受け取るのはマーカーの実装1件、返すのは本体の読み取りの結果である。
//! 読み手は検査を借り、`Mコマンド` を名乗る型の同一性の一覧を構築時に1度だけ組んで持つ。検査の型へメソッドを足さないのは、説明関数の観点と別の、読み方の責務だからである。
//! フィールドは、定義の本体の行を1行ずつ `名前: 型` として読む。型の表記を1つの名前として読み、その名前をフィールドの行の位置から型の定義の探索でたどり、
//! たどり着いた型の同一性(定義の位置のモジュール + 型名)が `Mコマンド` の実装の型の同一性の一覧にあるかで判定する。
//! 型の表記が1つの名前で読めないフィールド(`Vec<水平移動の操作>`・`Option<..>`・パスで修飾した名前)は、`Mコマンド` を名乗る型そのものを並べた形と確かめられない。

use std::collections::HashSet;
use std::path::Path;

use super::line_matching::{名前で読める表記, 波括弧が閉じる行, 語として現れるか};
use super::module_path::モジュールパス;
use super::syntax_checker::クレート構文検査;
use super::syntax_patterns::{Rust型種別, 型宣言の開始};
use super::trait_implementation::設計解釈マーカーの実装;
use super::type_definition::{型の在り処の問い, 定義ブロックの結果};
use super::フィールドの行::フィールドの名前と型の表記;
use super::設計解釈マーカーの一覧::設計解釈マーカー;

/// 構造体の本体を読んだ結果。
/// 構造体の宣言の行を見つけられなかったとき(定義が無いことと構造体でないことは、それぞれの検査が別に報告する)は `構造体の宣言が無い` である。
/// 本体を開いた波括弧が宣言の行で閉じる形(位置で並べたフィールドと1行に収めた本体)は、フィールドの型を確かめられないため `行ごとの本体でない` である。
pub(super) enum 構造体の本体の読み取り {
    構造体の宣言が無い,
    行ごとの本体でない,
    フィールドが無い,
    フィールドを判定した(Vec<フィールドの判定>), // フィールドを1つ以上読み、それぞれを判定した
}

/// フィールド1つの型の判定。
pub(super) enum フィールドの判定 {
    コマンドである,
    コマンドでない { 名前: String, 型名: String }, // 型をたどれたが、その型は `Mコマンド` を名乗らない
    名前と型として読めない { 行: String },         // 行を `名前: 型` として読めない
    一つの名前として読めない { 名前: String, 型の表記: String },
    定義を一意にたどれない { 名前: String, 型名: String },
}

impl 構造体の本体の読み取り {
    /// フィールドを1つ以上読み、そのどれもが `Mコマンド` を名乗る型か。
    pub(super) fn どのフィールドもコマンドか(&self) -> bool {
        match self {
            Self::フィールドを判定した(判定一覧) => 判定一覧.iter().all(|判定| matches!(判定, フィールドの判定::コマンドである)),
            Self::構造体の宣言が無い | Self::行ごとの本体でない | Self::フィールドが無い => false,
        }
    }
}

/// 構造体のフィールドを読み、型が `Mコマンド` を名乗るかを判定する読み手。
pub(super) struct 構造体のフィールドの読み手<'a> {
    検査: &'a クレート構文検査,
    コマンドの同一性一覧: HashSet<(モジュールパス, String)>,
}

impl<'a> 構造体のフィールドの読み手<'a> {
    /// 検査を借り、`Mコマンド` を名乗る型の同一性の一覧を組む。
    pub(super) fn 生成する(検査: &'a クレート構文検査) -> Self {
        let コマンドの同一性一覧 = 検査.設計解釈マーカーの実装一覧(設計解釈マーカー::Mコマンド).iter().map(|型| 検査.型の同一性(型)).collect();
        Self { 検査, コマンドの同一性一覧 }
    }

    /// マーカーを実装した型の構造体の定義の本体を読み、フィールドごとに型が `Mコマンド` を名乗るかを判定する。
    pub(super) fn 構造体のフィールドを読む(&self, 型: &設計解釈マーカーの実装) -> 構造体の本体の読み取り {
        let 定義ブロックの結果::見つかった { パス, モジュール, .. } = self.検査.型の定義ブロック(型) else {
            return 構造体の本体の読み取り::構造体の宣言が無い;
        };
        let Some((_, 行一覧)) = self.検査.ソース一覧.iter().find(|(候補, _)| *候補 == パス) else {
            return 構造体の本体の読み取り::構造体の宣言が無い;
        };
        let 字句位置一覧 = モジュールパス::ファイルのパスから求める(&パス).行ごとの字句位置一覧(行一覧);
        let 宣言の開始 = 型宣言の開始(Rust型種別::Struct, &型.型名);
        let Some(宣言の位置) = 行一覧.iter().zip(&字句位置一覧).position(|(行, 位置)| 語として現れるか(行, &宣言の開始) && 位置.モジュール == モジュール) else {
            return 構造体の本体の読み取り::構造体の宣言が無い;
        };
        // 本体を開いた波括弧が宣言の行で閉じない(閉じる行が宣言の行より後ろにある)ことで、名前付きのフィールドを行ごとに並べた本体と見分ける。
        let 終了 = 波括弧が閉じる行(行一覧, 宣言の位置);
        if 終了 == 宣言の位置 {
            return 構造体の本体の読み取り::行ごとの本体でない;
        }
        let 判定一覧: Vec<フィールドの判定> = 行一覧
            .iter()
            .enumerate()
            .take(終了)
            .skip(宣言の位置 + 1)
            .map(|(添字, 行)| (添字, 行.trim()))
            .filter(|(_, 行)| !行.is_empty() && !行.starts_with('#'))
            .map(|(添字, 行)| self.フィールドを判定する(&パス, 添字, 行))
            .collect();
        if 判定一覧.is_empty() {
            return 構造体の本体の読み取り::フィールドが無い;
        }
        構造体の本体の読み取り::フィールドを判定した(判定一覧)
    }

    // フィールドの1行を読み、その型が `Mコマンド` を名乗るかを判定する。
    fn フィールドを判定する(&self, パス: &Path, 添字: usize, 行: &str) -> フィールドの判定 {
        let Some((名前, 型の表記)) = フィールドの名前と型の表記(行) else {
            return フィールドの判定::名前と型として読めない { 行: 行.to_string() };
        };
        let Some(型名) = 名前で読める表記(型の表記) else {
            return フィールドの判定::一つの名前として読めない {
                名前: 名前.to_string(),
                型の表記: 型の表記.to_string(),
            };
        };
        let 問い = 型の在り処の問い {
            型名: &型名,
            参照元のパス: パス,
            参照元の行番号: 添字 + 1,
        };
        let モジュール = match self.検査.型の在り処を探す(&問い) {
            定義ブロックの結果::見つかった { モジュール, .. } => モジュール,
            定義ブロックの結果::見つからない | 定義ブロックの結果::複数ある | 定義ブロックの結果::別名のため取り込み元を求められない => {
                return フィールドの判定::定義を一意にたどれない { 名前: 名前.to_string(), 型名 };
            }
        };
        let 同一性 = (モジュール, 型名);
        if self.コマンドの同一性一覧.contains(&同一性) {
            return フィールドの判定::コマンドである;
        }
        フィールドの判定::コマンドでない {
            名前: 名前.to_string(), 型名: 同一性.1
        }
    }
}
