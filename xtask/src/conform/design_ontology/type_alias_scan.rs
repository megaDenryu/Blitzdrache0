//! ソースの1行が型の別名の宣言(`type 別名<..> = 右辺;`)を書き出すかを読む純粋な関数。受け取るのはコードだけの行の一覧と書き出しの行の添字、返すのは別名と右辺の組か、別名の宣言でないか、読み切れないかである。
//! 読む位置を限らないのは、名前の閉包(`marker_name_closure.rs`)が、関数の本体の中の `type` もマクロの本体の中の `type` も同じ辺として数えるためである。
//! 位置で絞ると、検査器が読まない位置に置いた別名が名前の閉包から漏れる。読む位置を広く取ることで漏れた辺が無くなり、増える辺は違反の側へ倒す近似になる。
//! 実装の本体の中の関連型(`type Output = Self;`)も同じ形で読む。名前の閉包は、関連型を右辺の名前から関連型の名前への片方向の辺にする(`marker_name_closure.rs`)。
//! 右辺を持たない関連型の宣言(`type Output;`・`type 状態: M状態 + PartialEq;`)は辺を作らないため、辺を作らない宣言を読んだと答える。境界の中の等式(`type A: 甲<X = Y>;`)を右辺と読み違えないよう、`=` はどの括弧の中でもない位置のものだけを探す。
//! rustfmt が長い宣言を `=` の後ろで折るため、宣言を終える `;` まで行を繋いでから読む(`statement_span.rs`)。右辺は括弧の中に `;` を持てる(`[規則; 2]`)ため、どの括弧の中でもない `;` で宣言を終える。
//! 読み切れない綴り(ファイルの最後まで `;` に届かない・`type` の後ろに別名の識別子が無い・型引数の山括弧が `;` までに閉じない・`=` の右辺が空である・右辺にマクロのメタ変数がある)は黙って飛ばさず、読み切れないと答える。読み口の全域性の検査(`token_tree_gate/readable_form_assertion.rs`)がそれを違反にする。

use super::declaration_brackets::{最上位のカンマで分ける, 見出しの括弧の深さ};
use super::declaration_prefix::属性と可視性を読み飛ばす;
use super::declaration_reading_outcome::{宣言を読んだ結末, 読めない宣言};
use super::line_matching::{先頭の型引数を分ける, 先頭の識別子};
use super::macro_metavariable::メタ変数を含むか;
use super::statement_span::{セミコロンまで繋いだ本文, 宣言を終えるセミコロン};

/// 型の別名の宣言1件。別名と、型引数の並び(山括弧の内側)と、右辺の表記(末尾の `;` と前後の空白を除いたもの)の組である。
pub struct 型の別名の宣言 {
    pub 別名: String,
    pub 型引数の並び: String,
    pub 右辺: String,
}

impl 型の別名の宣言 {
    /// 型引数の並びのうち、既定値(`T = 規則`)を持つ型の引数の表記の一覧。定数の引数(`const N: usize = 3`)と、境界の中の等式(`T: Iterator<Item = u8>`)は数えない。
    pub fn 既定値を持つ型の引数一覧(&self) -> Vec<&str> {
        最上位のカンマで分ける(&self.型引数の並び)
            .into_iter()
            .map(str::trim)
            .filter(|引数| !引数.starts_with("const ") && 最上位の等号より後ろ(引数).is_some())
            .collect()
    }
}

/// 添字の行が `type 別名<..> = 右辺;` を書き出すなら、宣言を終える `;` まで行を繋いで読んだ別名と右辺。
pub fn 型の別名の宣言を読む(行一覧: &[String], 添字: usize) -> 宣言を読んだ結末<型の別名の宣言> {
    let 書き出し = 行一覧.get(添字).map_or("", String::as_str);
    let Some(後ろ) = 属性と可視性を読み飛ばす(書き出し).strip_prefix("type").filter(|後ろ| 後ろ.starts_with(char::is_whitespace)) else {
        return 宣言を読んだ結末::その宣言でない;
    };
    let Some(宣言) = セミコロンまで繋いだ本文(後ろ, 行一覧.get(添字 + 1..).unwrap_or_default(), 宣言を終えるセミコロン::括弧の外の) else {
        return 読み切れない(書き出し, "`type` の宣言がファイルの最後まで `;` に届かない");
    };
    let 名前の表記 = 宣言.trim_start();
    let 別名 = 先頭の識別子(名前の表記);
    if 別名.is_empty() {
        return 読み切れない(書き出し, "`type` の後ろに別名の識別子が無い");
    }
    let 型引数から後ろ = 名前の表記.get(別名.len()..).unwrap_or_default().trim_start();
    let (型引数, 型引数より後ろ) = 先頭の型引数を分ける(型引数から後ろ);
    if 型引数から後ろ.starts_with('<') && 型引数.is_empty() && 型引数より後ろ.is_empty() {
        return 読み切れない(書き出し, "別名の型引数の山括弧が `;` までに閉じていない");
    }
    match 最上位の等号より後ろ(型引数より後ろ) {
        None => 宣言を読んだ結末::辺を作らない宣言を読んだ,
        Some(右辺) if 右辺.trim().is_empty() => 読み切れない(書き出し, "`=` の右辺が空である"),
        Some(右辺) if メタ変数を含むか(右辺) => 読み切れない(書き出し, "`=` の右辺にマクロのメタ変数がある。展開した先の名前を検査器は知らず、この別名が作る名前の辺を黙って落とす"),
        Some(右辺) => 宣言を読んだ結末::読めた(型の別名の宣言 {
            別名,
            型引数の並び: 型引数.to_string(),
            右辺: 右辺.trim().to_string(),
        }),
    }
}

fn 読み切れない(行: &str, 理由: &'static str) -> 宣言を読んだ結末<型の別名の宣言> {
    宣言を読んだ結末::読めない(読めない宣言 { 綴り: 行.trim().to_string(), 理由 })
}

// どの括弧の中でもない位置の最初の `=` より後ろ。境界の中の等式(`甲<X = Y>`)では分けない。等号がなければ無い。
fn 最上位の等号より後ろ(宣言: &str) -> Option<&str> {
    let mut 括弧 = 見出しの括弧の深さ::default();
    for (位置, 文字) in 宣言.char_indices() {
        if 文字 == '=' && 括弧.最上位か() {
            return 宣言.get(位置 + 1..);
        }
        括弧.括弧として数える(文字);
    }
    None
}
