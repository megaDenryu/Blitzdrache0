//! マーカーを名乗る型が実装している、走査範囲の外のトレイトの名前の台帳。検査器はそれらのトレイトの宣言を読めないため、既定の関数を検査しない。
//! 検査しないことの論証は「std が既定で与える可変の関数は、いずれも値の丸ごとの置き換えであり、正本が置き換えを禁じていない」であり、正本は `_doc/設計/設計オントロジー.md` 2.5.3 が持つ。
//! この論証は将来の依存の追加で腐るため、台帳が名前を固定する。台帳に無い名前が現れたら違反にし、台帳に載っているのに現れなくなった行も違反にする(`split_debt.rs`・`line_count_allowance.rs` の「台帳 + 陳腐化検査」と同じ様式)。
//! `derive` が生やす実装(`Debug`・`Clone`・`PartialEq`・`Eq`・`Hash`・`Copy`・`Default`)はソースの行に `impl` として現れないため、この台帳には載らない。

use std::path::{Path, PathBuf};

use super::super::violation::違反;
use super::external_trait_scan::走査範囲の外のトレイトの実装;

/// 台帳の1行。トレイトの名前と、その既定の関数が自己変更を与えないと言える根拠を持つ。根拠は、陳腐化の違反の文言がそのまま読み手へ返す。
pub struct 台帳の行 {
    pub トレイト名: &'static str,
    pub 自己変更しない根拠: &'static str,
}

/// 注意: 行を足してよいのは、そのトレイトの既定の関数が値の丸ごとの置き換えだけであると示せるときだけである。2026-09-23 に走査範囲を調べた時点で、マーカーを名乗る型が明示の `impl` で実装する走査範囲の外のトレイトは無い。
const 登録済みの行一覧: [台帳の行; 0] = [];

pub struct 走査範囲の外のトレイトの台帳 {
    行一覧: Vec<台帳の行>,
}

impl 走査範囲の外のトレイトの台帳 {
    /// 本番の検査が使う、登録済みの行の台帳。
    pub fn 登録済みの台帳() -> Self {
        Self {
            行一覧: Vec::from(登録済みの行一覧)
        }
    }

    /// 試験が行を与えて組む台帳。
    #[cfg(test)]
    pub const fn 行一覧から組む(行一覧: Vec<台帳の行>) -> Self {
        Self { 行一覧 }
    }

    /// 見つけた実装のうち台帳に無い名前のものと、台帳に載っているのに見つからなくなった行を、それぞれ違反にする。
    pub fn 突き合わせる(&self, 検出一覧: &[走査範囲の外のトレイトの実装]) -> Vec<違反> {
        let 載っているか = |名前: &str| self.行一覧.iter().any(|行| 行.トレイト名 == 名前);
        let mut 違反一覧: Vec<違反> = 検出一覧.iter().filter(|検出| !載っているか(&検出.トレイト名)).map(登録されていない違反).collect();
        違反一覧.extend(self.行一覧.iter().filter(|行| !検出一覧.iter().any(|検出| 検出.トレイト名 == 行.トレイト名)).map(台帳の行::陳腐化の違反));
        違反一覧
    }
}

fn 登録されていない違反(検出: &走査範囲の外のトレイトの実装) -> 違反 {
    let 説明 = format!(
        "設計オントロジー: M不変データ `{}` が、走査範囲の外のトレイト `{}` を実装している(検査器はその宣言を読めず、既定の関数を検査しない。既定の関数が値の丸ごとの置き換えだけであることを確かめ、その根拠を台帳 xtask/src/conform/design_ontology/external_trait_ledger.rs へ書く)",
        検出.マーカーの名前, 検出.トレイト名
    );
    違反::行単位(検出.パス.clone(), 検出.行番号, 説明)
}

impl 台帳の行 {
    fn 陳腐化の違反(&self) -> 違反 {
        let 説明 = format!(
            "設計オントロジー: 走査範囲の外のトレイトの台帳に載っている `{}` を実装する M不変データ の型が見つからない(台帳から削除する。載せた根拠は「{}」)",
            self.トレイト名, self.自己変更しない根拠
        );
        違反::ファイル単位(台帳のファイル(), 説明)
    }
}

// 陳腐化の違反が指すのは台帳そのものである。
fn 台帳のファイル() -> PathBuf {
    Path::new("xtask/src/conform/design_ontology/external_trait_ledger.rs").to_path_buf()
}
