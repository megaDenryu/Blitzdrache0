//! `crates` 配下の各クレートの `src` の下の全ソースを横断して行う構文検査。
//! 照合はすべてコメントと文字列を落としたコードだけの行に対して行う。行の中の文字列の照合は `line_matching.rs`、型の定義の探索は `type_definition.rs` が行う。

use std::collections::HashSet;
use std::path::PathBuf;

use super::super::violation::違反;
use super::impl_header::implの見出しを読む;
use super::line_matching::{トレイト実装の行のトレイトの位置, トレイト実装の行の対象の型の表記, 先頭の識別子, 語として現れるか};
use super::module_path::モジュールパス;
use super::pure_data_definition_law::定義が破った純粋データの規約の説明一覧;
use super::syntax_patterns::{self, Rust型種別, オントロジートレイト};
use super::type_definition::{型の定義を探す, 定義ブロックの結果};

use super::trait_implementation::トレイト実装型;

pub struct クレート構文検査 {
    pub(super) ソース一覧: Vec<(PathBuf, Vec<String>)>,
    pub(super) 違反一覧: Vec<違反>,
}

impl クレート構文検査 {
    pub const fn 生成する(ソース一覧: Vec<(PathBuf, Vec<String>)>) -> Self {
        Self { ソース一覧, 違反一覧: Vec::new() }
    }

    pub fn 違反一覧(self) -> Vec<違反> {
        self.違反一覧
    }

    /// 走査したソースのパスとコードだけの行の一覧。設計関係の抽出器が、同じ走査結果から自分の構文の読み取りを行うために借りる。
    pub fn ソース一覧(&self) -> &[(PathBuf, Vec<String>)] {
        &self.ソース一覧
    }

    /// `impl トレイト for 型` と `impl<T> トレイト for 型<T>` の行を集める(トレイトを書く位置が正規形の `マーカー名` か `blitz_design::マーカー名` のもの)。
    pub fn トレイト実装型一覧(&self, トレイト: オントロジートレイト) -> Vec<トレイト実装型> {
        let 修飾した名前 = format!("blitz_design::{}", トレイト.名前());
        let mut 型一覧 = Vec::new();
        for (パス, 行一覧) in &self.ソース一覧 {
            for (添字, _) in 行一覧.iter().enumerate() {
                let Some(見出し) = implの見出しを読む(行一覧, 添字) else {
                    continue;
                };
                if !トレイト実装の行のトレイトの位置(&見出し.表記).is_some_and(|位置| 位置 == トレイト.名前() || 位置 == 修飾した名前) {
                    continue;
                }
                let Some(対象の型の表記) = トレイト実装の行の対象の型の表記(&見出し.表記) else {
                    continue;
                };
                let 型名 = 先頭の識別子(対象の型の表記);
                if !型名.is_empty() {
                    型一覧.push(トレイト実装型 {
                        型名,
                        対象の型の表記: 対象の型の表記.to_string(),
                        パス: パス.clone(),
                        行番号: 添字 + 1,
                    });
                }
            }
        }
        型一覧
    }

    /// `M不変データ` とデータの役割のいずれかを実装する型を、型の同一性(定義の位置のモジュール + 型名)で重複を除いて集める。同じ型が複数の役割を持っても1回だけ返し、
    /// 報告する役割は最初に見つけた実装のものである。定義が一意に決まらない実装は実装の位置のモジュールで数える(その違反は別に出る)。
    pub fn 純粋データ規約の対象一覧(&self) -> Vec<(オントロジートレイト, トレイト実装型)> {
        let mut 済み = HashSet::new();
        let mut 対象一覧 = Vec::new();
        for トレイト in [オントロジートレイト::M不変データ].into_iter().chain(オントロジートレイト::純粋データの役割一覧()) {
            for 型 in self.トレイト実装型一覧(トレイト) {
                if 済み.insert(self.型の同一性(&型)) {
                    対象一覧.push((トレイト, 型));
                }
            }
        }
        対象一覧
    }

    /// 型の同一性(定義の位置のモジュール + 型名)。定義の位置のモジュールは、定義の行を囲む `mod 名 { … }` の並びまで繋いだものである。
    /// 定義が一意に決まらない実装は実装の見出しの行の位置のモジュールで数える(その違反は別に出る)。
    pub fn 型の同一性(&self, 型: &トレイト実装型) -> (モジュールパス, String) {
        let モジュール = match self.型の定義ブロック(型) {
            定義ブロックの結果::見つかった { モジュール, .. } => モジュール,
            定義ブロックの結果::見つからない | 定義ブロックの結果::複数ある | 定義ブロックの結果::別名のため取り込み元を求められない => 型.位置のモジュール(&self.ソース一覧),
        };
        (モジュール, 型.型名.clone())
    }

    /// 型の定義(直前の属性の行を含む)。実装の位置のモジュールの直下の定義、無ければ `use` で取り込んだモジュールの直下の定義を採り、決まらなければその旨を返す(`type_definition.rs`)。
    pub fn 型の定義ブロック(&self, 型: &トレイト実装型) -> 定義ブロックの結果 {
        型の定義を探す(&self.ソース一覧, 型)
    }

    /// 採った定義が `種別` のキーワードで始まるか。定義が一意に決まらないときは偽である。
    pub fn 型種別を満たしているか(&self, 種別: Rust型種別, 型: &トレイト実装型) -> bool {
        let 開始 = syntax_patterns::型宣言の開始(種別, &型.型名);
        match self.型の定義ブロック(型) {
            定義ブロックの結果::見つかった { 定義, .. } => 定義.lines().any(|行| 語として現れるか(行, &開始)),
            定義ブロックの結果::見つからない | 定義ブロックの結果::複数ある | 定義ブロックの結果::別名のため取り込み元を求められない => false,
        }
    }

    /// 採った定義が参照・生ポインタ・内部可変性を持つときの説明。定義が一意に決まらないときは空である。規約そのものは `pure_data_definition_law` が持つ。
    pub fn 純粋データの規約の違反一覧(&self, 型: &トレイト実装型) -> Vec<String> {
        match self.型の定義ブロック(型) {
            定義ブロックの結果::見つかった { 定義, .. } => 定義が破った純粋データの規約の説明一覧(&定義),
            定義ブロックの結果::見つからない | 定義ブロックの結果::複数ある | 定義ブロックの結果::別名のため取り込み元を求められない => Vec::new(),
        }
    }
}
