//! `M不変データ` の型が自己変更を与える根拠を探す検査。全ソースとトレイトの宣言の索引とモジュールの索引を保持し、型名と定義のパスを受けて、最初に見つけた根拠を返す。
//! 型に属する実装は、固有の実装とその型を対象にするトレイトの実装である。対象の型の表記は `implementation_binding.rs` の規則で定義へ結び付け、
//! 型名が一致するのに定義へ結び付けられない実装と、型の別名を通した実装も、黙って外さず根拠を探す(見つかれば結び付けられない実装という根拠にする)。
//! 実装の本体の直下の関数と、実装したトレイトの宣言の関数(既定の関数を含む。`trait_declaration_index.rs`)を `function_signature.rs` の規則で見る。対象が可変参照の実装は、関数を1つでも持てば可変とみなす。
//! 本体の直下のマクロの呼び出し(`body_macro_invocation.rs`)と、別名で取り込んだトレイトと、走査範囲に宣言が無く走査範囲の外のトレイトでもないトレイト(`implemented_trait.rs`)は、読めないため黙って通さず根拠にする。

use std::path::{Path, PathBuf};

use super::binding_outcome::実装の結び付け;
use super::body_macro_invocation::本体の直下のマクロの呼び出し;
use super::function_signature::{本体の直下の関数の署名一覧, 自己変更を問う対象};
use super::impl_header::implの見出しを読む;
use super::impl_syntax::{実装の種類, 実装の見出しの構文};
use super::implemented_trait::実装したトレイト;
use super::module_index::モジュールの索引;
use super::read_implementation::読んだ実装;
use super::self_modification_evidence::自己変更の根拠;
use super::trait_declaration_index::トレイトの宣言の索引;

/// 自己変更の根拠を探す相手の型。型名と、その型の定義を採ったファイルのパスの組である。
pub struct 検査する型の定義<'b> {
    pub 型名: &'b str,
    pub 定義のパス: &'b Path,
}

pub struct 自己変更の検査<'a> {
    pub(super) ソース一覧: &'a [(PathBuf, Vec<String>)],
    トレイトの索引: トレイトの宣言の索引,
    モジュールの索引: モジュールの索引<'a>,
}

impl<'a> 自己変更の検査<'a> {
    pub fn 生成する(ソース一覧: &'a [(PathBuf, Vec<String>)]) -> Self {
        Self {
            ソース一覧,
            トレイトの索引: トレイトの宣言の索引::全ソースから組む(ソース一覧),
            モジュールの索引: モジュールの索引::全ソースから組む(ソース一覧),
        }
    }

    /// その型が自己変更を与える根拠のうち、最初に見つけたもの。無ければ無い。
    pub fn 最初の自己変更の根拠(&self, 型: &検査する型の定義) -> Option<自己変更の根拠> {
        self.ソース一覧.iter().find_map(|(パス, 行一覧)| {
            (0..行一覧.len()).find_map(|開始| {
                let 見出し = implの見出しを読む(行一覧, 開始)?;
                self.実装の中の根拠(
                    &読んだ実装 {
                        パス, 行一覧, 行番号: 開始 + 1, 見出し
                    },
                    型,
                )
            })
        })
    }

    // 1つの実装が型に属するか、属するかを決められないなら、本体の直下の関数と実装したトレイトの宣言の関数から根拠を探す。全称の実装は別の問いが読む。
    fn 実装の中の根拠(&self, 実装: &読んだ実装, 型: &検査する型の定義) -> Option<自己変更の根拠> {
        let 構文 = 実装の見出しの構文::読む(&実装.見出し.表記)?;
        if 構文.全称の実装か() {
            return None;
        }
        let 結び付けられない理由 = match 実装.対象の型を結び付ける(&self.モジュールの索引, &構文.対象, 型) {
            実装の結び付け::別の型 => return None,
            実装の結び付け::検査している型 => None,
            実装の結び付け::結び付けられない(理由) => Some(理由),
        };
        let 対象 = 自己変更を問う対象 {
            型名: 構文.対象.名前(),
            可変参照を対象にするか: 構文.対象.可変参照か,
        };
        let 根拠 = self.実装が与える自己変更の根拠(実装, &構文.種類, &対象)?;
        Some(match 結び付けられない理由 {
            None => 根拠,
            Some(理由) => 自己変更の根拠::定義へ結び付けられない実装 {
                パス: 実装.パス.to_path_buf(),
                行番号: 実装.行番号,
                理由,
            },
        })
    }

    /// 実装の本体の直下の関数・本体の直下のマクロの呼び出し・実装したトレイトが、対象へ自己変更を与えるなら、その根拠。型に属するかは呼び出し側が確かめる。
    pub fn 実装が与える自己変更の根拠(&self, 実装: &読んだ実装, 種類: &実装の種類, 対象: &自己変更を問う対象) -> Option<自己変更の根拠> {
        let 本体 = 実装.見出し.本体の文字列(実装.行一覧);
        if let Some(関数) = 本体の直下の関数の署名一覧(&本体).into_iter().find(|関数| 対象.自己変更を与えるか(関数)) {
            return Some(自己変更の根拠::実装の関数 {
                パス: 実装.パス.to_path_buf(),
                行番号: 実装.行番号,
                関数名: 関数.名前,
            });
        }
        if let Some(マクロ名) = 本体の直下のマクロの呼び出し(&本体) {
            return Some(自己変更の根拠::本体のマクロの呼び出し {
                パス: 実装.パス.to_path_buf(),
                行番号: 実装.行番号,
                マクロ名,
            });
        }
        let 実装の種類::トレイトの実装 { トレイトの表記 } = 種類 else {
            return None;
        };
        (実装したトレイト { 実装, 表記: トレイトの表記 }).自己変更の根拠(&self.トレイトの索引, &self.モジュールの索引, 対象)
    }
}
