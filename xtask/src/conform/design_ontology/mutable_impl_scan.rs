//! `M不変データ` の型が自己変更を与える根拠を探す検査。全ソースとトレイトの宣言の索引と名前の言い換えの辺の一覧を保持し、マーカーを名乗る型の名前を受けて、当たった実装の全部を返す。
//! 検査器は、実装の対象がどの型を指すかを名前解決で求めない。マーカーの名前の閉包(`marker_name_closure.rs`)の名前が、実装の対象の表記に識別子の境界(`identifier_boundary.rs`)で現れれば、その実装を検査する。
//! 実装の在り処は問わない。関数の本体の中の実装も、波括弧付きのモジュールの中の実装も、マクロの本体の中の実装も、`#[cfg(..)]` が付いた実装も同じく検査する。
//! 名前解決をやめたのは、`use`・glob・再公開・別名・cfg・局所の項目・波括弧付きのモジュール・マクロの呼び出しの中を解く解き方に、名前を取りこぼす穴が繰り返し見つかったためである。名前で過大近似すると、その種類の穴が原理的に存在しなくなる。
//! 名前を経由しない書き方(対象の型と型の別名の右辺の先頭の射影とマクロ、`include!`)は、正規形の検査(`name_traceable_form_assertion.rs`)が落とす。
//! 対象が可変参照の実装は、関数を1つでも持てば可変とみなす。実装の本体の直下の関数と、実装したトレイトの宣言の関数(既定の関数を含む。`trait_declaration_index.rs`)を `function_signature.rs` の規則で見る。
//! 本体の直下のマクロの呼び出し(`body_macro_invocation.rs`)と、宣言の本体の直下でマクロを呼ぶトレイトは、生える関数を読めないため黙って通さず根拠にする。

use std::path::PathBuf;

use super::body_macro_invocation::本体の直下のマクロの呼び出し;
use super::function_signature::{本体の直下の関数の署名一覧, 自己変更を問う対象};
use super::identifier_boundary::識別子として現れるか;
use super::impl_header::implの見出しを読む;
use super::impl_syntax::実装の種類;
use super::implemented_trait::実装したトレイト;
use super::marker_name_closure::名前の言い換えの辺一覧;
use super::name_matched_implementation::名前が当たった自己変更の実装;
use super::read_implementation::読んだ実装;
use super::self_modification_evidence::自己変更の根拠;
use super::trait_declaration_index::トレイトの宣言の索引;

pub struct 自己変更の検査<'a> {
    pub(super) ソース一覧: &'a [(PathBuf, Vec<String>)],
    トレイトの索引: トレイトの宣言の索引,
    名前の辺一覧: 名前の言い換えの辺一覧,
}

impl<'a> 自己変更の検査<'a> {
    pub fn 生成する(ソース一覧: &'a [(PathBuf, Vec<String>)]) -> Self {
        Self {
            ソース一覧,
            トレイトの索引: トレイトの宣言の索引::全ソースから組む(ソース一覧),
            名前の辺一覧: 名前の言い換えの辺一覧::全ソースから組む(ソース一覧),
        }
    }

    /// マーカーを名乗る型の名前の閉包のどれかを対象の表記に含み、しかも自己変更の根拠を持つ実装の全部。並びはソースの並びと行の順である。
    pub fn 名前が当たった自己変更の実装一覧(&self, マーカーの名前: &str) -> Vec<名前が当たった自己変更の実装> {
        let 名前の集合 = self.名前の辺一覧.閉包(マーカーの名前);
        let mut 一覧 = Vec::new();
        for (パス, 行一覧) in self.ソース一覧 {
            for 開始 in 0..行一覧.len() {
                let Some(見出し) = implの見出しを読む(行一覧, 開始) else {
                    continue;
                };
                let 鍵の表記 = 見出し.台帳の鍵の表記();
                let 実装 = 読んだ実装 {
                    パス, 行一覧, 行番号: 開始 + 1, 見出し
                };
                一覧.extend(self.実装の中の根拠(&実装, &名前の集合).map(|根拠| 名前が当たった自己変更の実装 {
                    マーカーの名前: マーカーの名前.to_string(),
                    パス: パス.clone(),
                    見出し: 鍵の表記,
                    根拠,
                }));
            }
        }
        一覧
    }

    // 1つの実装の対象の表記に名前の集合のどれかが識別子として現れるなら、その名前で自己変更の根拠を探す。全称の実装は別の問いが読む。
    fn 実装の中の根拠(&self, 実装: &読んだ実装, 名前の集合: &[String]) -> Option<自己変更の根拠> {
        let 構文 = 実装.見出し.構文を読む()?;
        if 構文.全称の実装か() {
            return None;
        }
        名前の集合.iter().find_map(|名前| {
            識別子として現れるか(構文.対象.表記(), 名前).then(|| {
                self.実装が与える自己変更の根拠(
                    実装,
                    &構文.種類,
                    &自己変更を問う対象 {
                        型名: 名前,
                        可変参照を対象にするか: 構文.対象.可変参照か,
                    },
                )
            })?
        })
    }

    /// 実装の本体の直下の関数・本体の直下のマクロの呼び出し・実装したトレイトの宣言が、対象へ自己変更を与えるなら、その根拠。対象が型に属するかは呼び出し側が確かめる。
    pub fn 実装が与える自己変更の根拠(&self, 実装: &読んだ実装, 種類: &実装の種類, 対象: &自己変更を問う対象) -> Option<自己変更の根拠> {
        let (パス, 行番号) = (実装.パス.to_path_buf(), 実装.行番号);
        let 本体 = 実装.見出し.本体の文字列(実装.行一覧);
        if let Some(関数) = 本体の直下の関数の署名一覧(&本体).into_iter().find(|関数| 対象.自己変更を与えるか(関数)) {
            return Some(自己変更の根拠::実装の関数 {
                パス,
                行番号,
                対象の名前: 対象.型名.to_string(),
                関数名: 関数.名前,
            });
        }
        if let Some(マクロ名) = 本体の直下のマクロの呼び出し(&本体) {
            return Some(自己変更の根拠::本体のマクロの呼び出し { パス, 行番号, マクロ名 });
        }
        let 実装の種類::トレイトの実装 { トレイトの表記 } = 種類 else {
            return None;
        };
        (実装したトレイト {
            表記: トレイトの表記, パス: 実装.パス, 行番号
        })
        .自己変更の根拠(&self.トレイトの索引, &self.名前の辺一覧, 対象)
    }
}
