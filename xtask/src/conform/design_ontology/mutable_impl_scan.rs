//! `M不変データ` の型が自己変更を与える根拠を探す検査。全ソースを保持し、型名と定義のパスを受けて、最初に見つけた根拠を返す。
//! 型に属する実装は、固有の実装とその型を対象にするトレイトの実装である。対象の型の表記はパスの最後の要素で型名に照らし、
//! パスの修飾があればそのモジュールパスを定義のモジュールパスと突き合わせ、無ければ定義と同じファイルか型を取り込んだファイルに限る(`read_implementation.rs`)。
//! 実装の本体の直下の関数を `function_signature.rs` の規則で見る。対象が可変参照の実装は、関数を1つでも持てば可変とみなす。

use std::path::{Path, PathBuf};

use super::function_signature::{本体の直下の関数の署名一覧, 自己変更を問う対象};
use super::impl_header::implの見出しを読む;
use super::impl_syntax::実装の見出しの構文;
use super::read_implementation::読んだ実装;
use super::self_modification_evidence::自己変更の根拠;

/// 自己変更の根拠を探す相手の型。型名と、その型の定義を採ったファイルのパスの組である。
pub struct 検査する型の定義<'b> {
    pub 型名: &'b str,
    pub 定義のパス: &'b Path,
}

pub struct 自己変更の検査<'a> {
    ソース一覧: &'a [(PathBuf, Vec<String>)],
}

impl<'a> 自己変更の検査<'a> {
    pub const fn 生成する(ソース一覧: &'a [(PathBuf, Vec<String>)]) -> Self {
        Self { ソース一覧 }
    }

    /// その型が自己変更を与える根拠のうち、最初に見つけたもの。無ければ無い。
    pub fn 最初の自己変更の根拠(&self, 型: &検査する型の定義) -> Option<自己変更の根拠> {
        self.ソース一覧.iter().find_map(|(パス, 行一覧)| {
            (0..行一覧.len()).find_map(|開始| {
                let 見出し = implの見出しを読む(行一覧, 開始)?;
                Self::実装の中の根拠(
                    &読んだ実装 {
                        パス, 行一覧, 行番号: 開始 + 1, 見出し
                    },
                    型,
                )
            })
        })
    }

    // 1つの実装が型に属するなら、本体の直下の関数から根拠を探す。
    fn 実装の中の根拠(実装: &読んだ実装, 型: &検査する型の定義) -> Option<自己変更の根拠> {
        let 構文 = 実装の見出しの構文::読む(&実装.見出し.表記)?;
        if 構文.対象.名前() != 型.型名 || !実装.定義を指すか(&構文.対象, 型.定義のパス) {
            return None;
        }
        let 対象 = 自己変更を問う対象 {
            型名: 型.型名,
            可変参照を対象にするか: 構文.対象.可変参照か,
        };
        let 関数 = 本体の直下の関数の署名一覧(&実装.見出し.本体の文字列(実装.行一覧)).into_iter().find(|関数| 対象.自己変更を与えるか(関数))?;
        Some(自己変更の根拠::実装の関数 {
            パス: 実装.パス.to_path_buf(),
            行番号: 実装.行番号,
            関数名: 関数.名前,
        })
    }
}
