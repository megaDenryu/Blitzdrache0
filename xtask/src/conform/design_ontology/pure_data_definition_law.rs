//! 純粋データの役割を持つ型の定義に当てる禁止事項。受け取るのは採った定義の本文、返すのは破った規約の説明の一覧である。
//!
//! 禁じる構文の一覧と、破れ1件ごとの報告の文言をこのモジュールだけが持つ。構文検査の型が持つと、
//! ソースを走査して定義を採るという責務と、採った本文へ当てる規約の中身が同じ型へ溜まる。
//! 状態を1つも持たない規約であるため、フィールドの無い型へ包まず自由関数で置く(参照: グローバルCLAUDE.md「Rustの書き方の選択」条5(a))。
//! 参照: `_doc/設計/設計オントロジー.md` 第2節。

/// 定義が持ってはならない内部可変性の型。名前が現れることで判定するため、修飾を書いた表記にも当たる。
const 内部可変性の型一覧: [&str; 5] = ["RefCell", "Mutex", "RwLock", "Cell", "Atomic"];

/// 定義の本文が参照・生ポインタ・内部可変性を持つときの説明。どれも持たなければ空である。
pub fn 定義が破った純粋データの規約の説明一覧(定義: &str) -> Vec<String> {
    let mut 説明一覧 = Vec::new();
    if 定義.contains('&') {
        説明一覧.push("の定義は参照(&)を持てません".to_string());
    }
    if 定義.contains("*const") || 定義.contains("*mut") {
        説明一覧.push("の定義は生ポインタを持てません".to_string());
    }
    if let Some(型) = 内部可変性の型一覧.iter().find(|型| 定義.contains(*型)) {
        説明一覧.push(format!("の定義は内部可変性 `{型}` を持てません"));
    }
    説明一覧
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 参照と生ポインタと内部可変性をそれぞれ1件の説明にする() {
        assert!(定義が破った純粋データの規約の説明一覧("struct 位置 { 東: f32 }").is_empty());
        assert_eq!(定義が破った純粋データの規約の説明一覧("struct 借り<'a> { 元: &'a str }").len(), 1);
        assert_eq!(定義が破った純粋データの規約の説明一覧("struct 生ポインタ持ち { 先: *const u8 }").len(), 1);
        assert_eq!(定義が破った純粋データの規約の説明一覧("struct 箱 { 中: RefCell<u8> }").len(), 1);
    }
}
