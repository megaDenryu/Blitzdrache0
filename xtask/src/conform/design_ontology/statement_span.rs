//! 宣言を書き出した行から、その宣言を終える `;` までを行をまたいで繋ぐ純粋な関数。受け取るのは書き出しの行の予約語より後ろと続きの行の一覧、返すのは `;` の手前までの本文である。
//! rustfmt は表示の幅(`max_width = 250`)を超える宣言を折る(`type 別名 =` の後ろで右辺を次の行へ送る)。日本語の識別子は表示の幅を2つ使うため、125文字でこの幅に届く。
//! 1行しか読まないと、折れた正当な宣言を読み切れないと誤って違反にするため、読み口は宣言を終える `;` まで行を繋いでから読む。
//! どの `;` が宣言を終えるかは宣言の種類で違う。`type` の右辺は括弧の中に `;` を持てる(`[規則; 2]`)ため括弧の外の `;` で終え、`use` の木は `;` を持てないため最初の `;` で終える。
//! 括弧の外かは、丸括弧・角括弧・波括弧だけで数え、山括弧を数えない。配列の長さの式のシフト(`[u8; 1 << 4]`・`[u8; 16 >> 2]`)を山括弧と読むと、宣言を終える `;` を見失うためである。`;` は山括弧の中に直に書けず、必ずこの3つの括弧のどれかの中に在る。

/// 宣言を終える `;` の探し方。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 宣言を終えるセミコロン {
    最初の,
    括弧の外の,
}

/// 書き出しの残りと続きの行を空白で繋ぎ、宣言を終える `;` の手前までを本文として返す。ファイルの最後まで宣言を終える `;` が現れなければ無い。
pub fn セミコロンまで繋いだ本文(書き出しの残り: &str, 続きの行一覧: &[String], 終え方: 宣言を終えるセミコロン) -> Option<String> {
    let mut 本文 = String::new();
    let mut 深さ = 0usize;
    for 部分 in std::iter::once(書き出しの残り).chain(続きの行一覧.iter().map(String::as_str)) {
        if !本文.is_empty() {
            本文.push(' ');
        }
        for 文字 in 部分.chars() {
            match 文字 {
                ';' if 終え方 == 宣言を終えるセミコロン::最初の || 深さ == 0 => return Some(本文),
                '(' | '[' | '{' => 深さ += 1,
                ')' | ']' | '}' => 深さ = 深さ.saturating_sub(1),
                _ => {}
            }
            本文.push(文字);
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::{セミコロンまで繋いだ本文, 宣言を終えるセミコロン};

    #[test]
    fn 折れた宣言をセミコロンまで繋ぐ() {
        let 続き = vec!["    crate::a::規則;".to_string(), "type 次 = u8;".to_string()];
        assert_eq!(セミコロンまで繋いだ本文(" 別名 =", &続き, 宣言を終えるセミコロン::括弧の外の).as_deref(), Some(" 別名 =     crate::a::規則"));
        assert_eq!(セミコロンまで繋いだ本文(" a::{b, c}; ", &[], 宣言を終えるセミコロン::最初の).as_deref(), Some(" a::{b, c}"));
    }

    #[test]
    fn 山括弧を数えずシフトと関数の型の後ろのセミコロンで終える() {
        for (書き出し, 期待) in [(" F = fn() -> u8;", " F = fn() -> u8"), (" 表 = [u8; 1 << 4];", " 表 = [u8; 1 << 4]"), (" 表 = [u8; 16 >> 2];", " 表 = [u8; 16 >> 2]")] {
            assert_eq!(セミコロンまで繋いだ本文(書き出し, &[], 宣言を終えるセミコロン::括弧の外の).as_deref(), Some(期待));
        }
    }

    #[test]
    fn 括弧の外のセミコロンは括弧の中のセミコロンで終えない() {
        assert_eq!(セミコロンまで繋いだ本文(" 配列 = [規則; 2];", &[], 宣言を終えるセミコロン::括弧の外の).as_deref(), Some(" 配列 = [規則; 2]"));
        assert_eq!(セミコロンまで繋いだ本文(" 配列 = [規則; 2];", &[], 宣言を終えるセミコロン::最初の).as_deref(), Some(" 配列 = [規則"));
    }

    #[test]
    fn ファイルの最後までセミコロンが無ければ無い() {
        assert!(セミコロンまで繋いだ本文(" 別名<T>", &["    = Vec<T>".to_string()], 宣言を終えるセミコロン::括弧の外の).is_none());
        assert!(セミコロンまで繋いだ本文(" a::{b, c", &[], 宣言を終えるセミコロン::最初の).is_none());
    }
}
