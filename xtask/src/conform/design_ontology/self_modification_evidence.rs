//! `M不変データ` の型が自己変更を与える根拠1件と、その根拠を違反の説明へ書く文言。
//! 本体の直下のマクロの呼び出しと、宣言の本体の直下でマクロを呼ぶトレイトを根拠に数えるのは、検査器がマクロを展開できず、生える関数の署名を読めないためである。
//! 説明が過大近似であることを書くのは、実装を集める鍵が対象の表記と型引数の並びの境界と `where` 句と関数の署名の境界に現れる名前であり、対象が裸の型名でない実装(型を包む実装・別名を通した実装・同じ名前の別の型の実装・境界で型を指すだけの実装)も当たるためである。
//! 説明には名前が当たった場所を書く。読み手が、どの表記を直すか、どの区分で台帳へ載せるかを決めるためである。

use std::path::PathBuf;

/// 過大近似であることを読み手へ伝える添え書き。自己変更を与える関数の根拠の説明がこの1文で閉じる。
const 過大近似の断り: &str = "この検査は実装の対象の型の表記と型引数の並びの境界と `where` 句と関数の署名の境界に現れる名前による過大近似であり、マーカーの型を書き換えない実装も当たる";

/// 自己変更を問う名前が、実装の見出しのどこに当たったか。境界で当たった実装は、境界がその型を指すため、値で受ける `self` を含む関数を1つでも持てば違反にする。
#[derive(Clone, Copy)]
pub enum 名前が当たった場所 {
    /// 実装の対象の型の表記
    対象の型の表記,
    /// 型引数の並びの境界
    型引数の並びの境界,
    /// `where` 句
    境界の句,
    /// 関数の型引数の並びの境界・関数の `where` 句・引数の `impl Trait` のどれか
    関数の署名の境界,
    /// 全称の実装の型引数か、マクロの本体の中のメタ変数か `Self`。検査器が対象の型を決められない実装の自分の型である
    決められない対象の型,
}

pub enum 自己変更の根拠 {
    /// 名前が見出しに当たった実装の、本体の直下の関数。行番号は実装の見出しの行である
    実装の関数 {
        パス: PathBuf,
        行番号: usize,
        対象の名前: String,
        当たった場所: 名前が当たった場所,
        関数名: String,
    },
    /// その実装が実装したトレイトの宣言の関数(既定の関数を含む)。同名の宣言の件数は、名前で引いた宣言が何件あったかである
    トレイトの宣言の関数 {
        パス: PathBuf,
        行番号: usize,
        対象の名前: String,
        当たった場所: 名前が当たった場所,
        トレイト名: String,
        関数名: String,
        同名の宣言の件数: usize,
    },
    /// 宣言の本体の直下で呼んだマクロが生やす既定の関数を読めないトレイト
    宣言を完全に読めないトレイト { パス: PathBuf, 行番号: usize, トレイト名: String, マクロ名: String },
    /// 本体の直下で呼んだマクロが生やす関数を読めない実装
    本体のマクロの呼び出し { パス: PathBuf, 行番号: usize, マクロ名: String },
}

impl 自己変更の根拠 {
    pub fn 説明(&self) -> String {
        match self {
            Self::実装の関数 {
                パス,
                行番号,
                対象の名前,
                当たった場所,
                関数名,
            } => 自己変更の説明(対象の名前, *当たった場所, &format!("{}:{行番号} の実装が、関数 `{関数名}` を持つ", パス.display())),
            Self::トレイトの宣言の関数 {
                パス,
                行番号,
                対象の名前,
                当たった場所,
                トレイト名,
                関数名,
                同名の宣言の件数,
            } => {
                let 件数 = if *同名の宣言の件数 >= 2 {
                    format!("(走査範囲に同名の宣言が{同名の宣言の件数}件あり、検査器は名前で引くためすべてを見る。名前を一意にする)")
                } else {
                    String::new()
                };
                自己変更の説明(対象の名前, *当たった場所, &format!("{}:{行番号} の実装が、トレイト `{トレイト名}`{件数} の宣言の関数 `{関数名}` を継ぐ", パス.display()))
            }
            Self::宣言を完全に読めないトレイト {
                パス, 行番号, トレイト名, マクロ名
            } => format!(
                "の {}:{行番号} のトレイトの実装は、宣言の本体の直下でマクロ `{マクロ名}!` を呼ぶトレイト `{トレイト名}` を実装しており、生える既定の関数を検査できません(関数を宣言の本体へ直接書く)",
                パス.display()
            ),
            Self::本体のマクロの呼び出し { パス, 行番号, マクロ名 } => {
                format!("の {}:{行番号} の実装は、本体の直下でマクロ `{マクロ名}!` を呼んでおり、生える関数を検査できません(関数を本体へ直接書く)", パス.display())
            }
        }
    }
}

fn 自己変更の説明(対象の名前: &str, 当たった場所: 名前が当たった場所, 場所: &str) -> String {
    format!("は自分の型への可変参照を受け手か引数に持つ関数を持てません(M不変データは自己変更しない。{}{場所}。{過大近似の断り})", 当たった場所.説明(対象の名前))
}

impl 名前が当たった場所 {
    // 違反の説明の、名前がどこに当たったかを言う部分。
    fn 説明(self, 名前: &str) -> String {
        match self {
            Self::対象の型の表記 => format!("実装の対象の型の表記に名前 `{名前}` を識別子として含む"),
            Self::型引数の並びの境界 => format!("型引数の並びの境界に名前 `{名前}` を識別子として含み、境界がその型を指すため値で受ける `self` の関数も数える"),
            Self::境界の句 => format!("`where` 句に名前 `{名前}` を識別子として含み、境界がその型を指すため値で受ける `self` の関数も数える"),
            Self::関数の署名の境界 => format!("関数の署名の境界(型引数の並びの境界・`where` 句・引数の `impl Trait`)の可変の借用を与えるトレイトの型引数に名前 `{名前}` を識別子として含み、その関数が境界を通してその型を書き換えうる"),
            Self::決められない対象の型 => format!("対象の型を決められない実装の自分の型 `{名前}` について問う"),
        }
    }
}
