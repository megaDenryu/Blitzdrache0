//! `M不変データ` の型が自己変更を与える根拠1件と、その根拠を違反の説明へ書く文言。
//! 別名で取り込んだトレイトの実装を根拠に数えるのは、宣言を引けないトレイトを黙って走査範囲の外として通さないためである。

use std::path::PathBuf;

pub enum 自己変更の根拠 {
    実装の関数 { パス: PathBuf, 行番号: usize, 関数名: String }, // 型に属する実装の本体の直下の関数。行番号は実装の見出しの行である
    トレイトの宣言の関数 { トレイト名: String, 関数名: String }, // 実装したトレイトの宣言の関数(既定の関数を含む)
    別名で取り込んだトレイト { パス: PathBuf, 行番号: usize, 別名: String },
}

impl 自己変更の根拠 {
    pub fn 説明(&self) -> String {
        let 場所 = match self {
            Self::実装の関数 { パス, 行番号, 関数名 } => format!("{}:{行番号} の実装の関数 `{関数名}`", パス.display()),
            Self::トレイトの宣言の関数 { トレイト名, 関数名 } => format!("実装したトレイト `{トレイト名}` の宣言の関数 `{関数名}`"),
            Self::別名で取り込んだトレイト { パス, 行番号, 別名 } => {
                return format!(
                    "の {}:{行番号} のトレイトの実装は、use の別名 `{別名}` で取り込んだトレイトを実装しており、宣言の関数を検査できません(別名を付けずに取り込む)",
                    パス.display()
                );
            }
        };
        format!("は自分の型への可変参照を受け手か引数に持つ関数を持てません(M不変データは自己変更しない。{場所})")
    }
}
