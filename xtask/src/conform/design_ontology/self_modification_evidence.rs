//! `M不変データ` の型が自己変更を与える根拠1件と、その根拠を違反の説明へ書く文言。
//! 本体の直下のマクロの呼び出しと、宣言の本体の直下でマクロを呼ぶトレイトを根拠に数えるのは、検査器がマクロを展開できず、生える関数の署名を読めないためである。
//! 説明が過大近似であることを書くのは、実装を集める鍵が対象の表記に現れる名前であり、対象が裸の型名でない実装(型を包む実装・別名を通した実装・同じ名前の別の型の実装)も当たるためである。

use std::path::PathBuf;

/// 過大近似であることを読み手へ伝える添え書き。自己変更を与える関数の根拠の説明がこの1文で閉じる。
const 過大近似の断り: &str = "この検査は対象の表記に現れる名前による過大近似であり、対象が裸の型名でない実装も当たる";

pub enum 自己変更の根拠 {
    /// 名前を対象の表記に含む実装の、本体の直下の関数。行番号は実装の見出しの行である
    実装の関数 { パス: PathBuf, 行番号: usize, 対象の名前: String, 関数名: String },
    /// その実装が実装したトレイトの宣言の関数(既定の関数を含む)。同名の宣言の件数は、名前で引いた宣言が何件あったかである
    トレイトの宣言の関数 {
        パス: PathBuf,
        行番号: usize,
        対象の名前: String,
        トレイト名: String,
        関数名: String,
        同名の宣言の件数: usize,
    },
    /// 宣言の本体の直下で呼んだマクロが生やす既定の関数を読めないトレイト
    宣言を完全に読めないトレイト { パス: PathBuf, 行番号: usize, トレイト名: String, マクロ名: String },
    /// 本体の直下で呼んだマクロが生やす関数を読めない実装
    本体のマクロの呼び出し { パス: PathBuf, 行番号: usize, マクロ名: String },
}

impl 自己変更の根拠 {
    pub fn 説明(&self) -> String {
        match self {
            Self::実装の関数 { パス, 行番号, 対象の名前, 関数名 } => 自己変更の説明(対象の名前, &format!("{}:{行番号} の実装が、関数 `{関数名}` を持つ", パス.display())),
            Self::トレイトの宣言の関数 {
                パス,
                行番号,
                対象の名前,
                トレイト名,
                関数名,
                同名の宣言の件数,
            } => {
                let 件数 = if *同名の宣言の件数 >= 2 {
                    format!("(走査範囲に同名の宣言が{同名の宣言の件数}件あり、検査器は名前で引くためすべてを見る。名前を一意にする)")
                } else {
                    String::new()
                };
                自己変更の説明(対象の名前, &format!("{}:{行番号} の実装が、トレイト `{トレイト名}`{件数} の宣言の関数 `{関数名}` を継ぐ", パス.display()))
            }
            Self::宣言を完全に読めないトレイト {
                パス, 行番号, トレイト名, マクロ名
            } => format!(
                "の {}:{行番号} のトレイトの実装は、宣言の本体の直下でマクロ `{マクロ名}!` を呼ぶトレイト `{トレイト名}` を実装しており、生える既定の関数を検査できません(関数を宣言の本体へ直接書く)",
                パス.display()
            ),
            Self::本体のマクロの呼び出し { パス, 行番号, マクロ名 } => {
                format!("の {}:{行番号} の実装は、本体の直下でマクロ `{マクロ名}!` を呼んでおり、生える関数を検査できません(関数を本体へ直接書く)", パス.display())
            }
        }
    }
}

fn 自己変更の説明(対象の名前: &str, 場所: &str) -> String {
    format!("は自分の型への可変参照を受け手か引数に持つ関数を持てません(M不変データは自己変更しない。対象の表記に名前 `{対象の名前}` を識別子として含む{場所}。{過大近似の断り})")
}
