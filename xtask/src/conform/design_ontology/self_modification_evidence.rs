//! `M不変データ` の型が自己変更を与える根拠1件と、その根拠を違反の説明へ書く文言。
//! 別名で取り込んだトレイト・走査範囲に宣言が無いトレイト・本体の直下のマクロの呼び出し・定義へ結び付けられない実装を根拠に数えるのは、検査器が読めないものを黙って通さないためである。

use std::path::PathBuf;

use super::binding_outcome::結び付けられない理由;

pub enum 自己変更の根拠 {
    実装の関数 { パス: PathBuf, 行番号: usize, 関数名: String }, // 型に属する実装の本体の直下の関数。行番号は実装の見出しの行である
    トレイトの宣言の関数 { トレイト名: String, 関数名: String }, // 実装したトレイトの宣言の関数(既定の関数を含む)
    別名で取り込んだトレイト { パス: PathBuf, 行番号: usize, 別名: String },
    宣言を読めないトレイト { パス: PathBuf, 行番号: usize, トレイトの表記: String },         // 索引に宣言が無く、走査範囲の外のトレイトでもない
    本体のマクロの呼び出し { パス: PathBuf, 行番号: usize, マクロ名: String },               // 本体の直下で呼んだマクロが生やす関数を読めない
    定義へ結び付けられない実装 { パス: PathBuf, 行番号: usize, 理由: 結び付けられない理由 }, // 型名は一致するが定義へ結び付けられず、自己変更の根拠を持つ実装
}

impl 自己変更の根拠 {
    pub fn 説明(&self) -> String {
        let 場所 = match self {
            Self::実装の関数 { パス, 行番号, 関数名 } => format!("{}:{行番号} の実装の関数 `{関数名}`", パス.display()),
            Self::トレイトの宣言の関数 { トレイト名, 関数名 } => format!("実装したトレイト `{トレイト名}` の宣言の関数 `{関数名}`"),
            Self::別名で取り込んだトレイト { パス, 行番号, 別名 } => {
                return format!(
                    "の {}:{行番号} のトレイトの実装は、use の別名 `{別名}` で取り込んだトレイトを実装しており、宣言の関数を検査できません(別名を付けずに取り込む)",
                    パス.display()
                );
            }
            Self::宣言を読めないトレイト { パス, 行番号, トレイトの表記 } => {
                return format!(
                    "の {}:{行番号} のトレイトの実装は、走査範囲に宣言が無いトレイト `{トレイトの表記}` を実装しており、宣言の関数を検査できません(std・core・alloc・外部の依存クレートのトレイトでも、prelude の名前でもない)",
                    パス.display()
                );
            }
            Self::本体のマクロの呼び出し { パス, 行番号, マクロ名 } => {
                return format!("の {}:{行番号} の実装は、本体の直下でマクロ `{マクロ名}!` を呼んでおり、生える関数を検査できません(関数を本体へ直接書く)", パス.display());
            }
            Self::定義へ結び付けられない実装 { パス, 行番号, 理由 } => {
                return format!(
                    "と同じ名前を対象にする {}:{行番号} の実装は、対象の型を定義へ結び付けられず({})、しかも自己変更を与える根拠を持ちます(定義のモジュールを名指すパスか use で書く)",
                    パス.display(),
                    理由.説明()
                );
            }
        };
        format!("は自分の型への可変参照を受け手か引数に持つ関数を持てません(M不変データは自己変更しない。{場所})")
    }
}
