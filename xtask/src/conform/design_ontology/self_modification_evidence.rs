//! `M不変データ` の型が自己変更を与える根拠1件と、その根拠を違反の説明へ書く文言。

use std::path::PathBuf;

pub enum 自己変更の根拠 {
    実装の関数 { パス: PathBuf, 行番号: usize, 関数名: String }, // 型に属する実装の本体の直下の関数。行番号は実装の見出しの行である
}

impl 自己変更の根拠 {
    pub fn 説明(&self) -> String {
        let 場所 = match self {
            Self::実装の関数 { パス, 行番号, 関数名 } => format!("{}:{行番号} の実装の関数 `{関数名}`", パス.display()),
        };
        format!("は自分の型への可変参照を受け手か引数に持つ関数を持てません(M不変データは自己変更しない。{場所})")
    }
}
