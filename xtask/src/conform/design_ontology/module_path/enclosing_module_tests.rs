//! 行ごとの字句位置(`module_path/enclosing_module.rs`)の試験。入れ子のモジュールの名前の繋ぎ方と、モジュールの直下・マクロの呼び出しの中・局所の位置の区分を固定する。

use super::enclosing_module::字句位置の区分;
use super::モジュールパス;

fn 行一覧(行: &[&str]) -> Vec<String> {
    行.iter().map(|行| (*行).to_string()).collect()
}

#[test]
fn 入れ子のモジュールの名前を外側から繋ぎ関数の本体の波括弧はモジュールに数えない() {
    let 行一覧 = 行一覧(&["mod 丙 {", "    fn f() {", "        let _ = 1;", "    }", "    pub(crate) mod 甲 {", "        pub trait 変更 {}", "    }", "}", "trait 外 {}"]);
    let 表記一覧: Vec<String> = モジュールパス::区切り一覧から組む(&["a", "x"]).行ごとの字句位置一覧(&行一覧).iter().map(|位置| 位置.モジュール.表記().to_string()).collect();
    assert_eq!(表記一覧, ["a::x", "a::x::丙", "a::x::丙", "a::x::丙", "a::x::丙", "a::x::丙::甲", "a::x::丙::甲", "a::x::丙", "a::x"]);
}

#[test]
fn 開いている波括弧がすべてモジュールの本体である行だけがモジュールの直下にある() {
    let 行一覧 = 行一覧(&[
        "use a::b;",
        "fn f() {",
        "    use a::c;",
        "    mod 内 {",
        "        use a::d;",
        "    }",
        "}",
        "mod 外 {",
        "    use a::e;",
        "    impl X {",
        "        type Y = u8;",
        "    }",
        "}",
    ]);
    let 直下か一覧: Vec<bool> = モジュールパス::区切り一覧から組む(&["a"]).行ごとの字句位置一覧(&行一覧).iter().map(|位置| 位置.モジュールの直下か()).collect();
    assert_eq!(直下か一覧, [true, true, false, false, false, false, false, true, true, true, false, false, true]);
}

#[test]
fn 項目の位置で波括弧を使って呼んだマクロの本体はマクロの呼び出しの中でありマクロの定義と局所のマクロは局所の位置である() {
    let 行一覧 = 行一覧(&[
        "素通し! {",
        "    pub trait 変更 {",
        "        fn 変える(&mut self);",
        "    }",
        "    use crate::x::規則 as 別名;",
        "}",
        "macro_rules! 定義 {",
        "    () => {};",
        "}",
        "fn f() {",
        "    別! {",
        "        struct 局所;",
        "    }",
        "}",
        "#[cfg(test)] crate::m::包む! {",
        "    struct 型;",
        "}",
    ]);
    let 区分一覧: Vec<字句位置の区分> = モジュールパス::区切り一覧から組む(&["a"]).行ごとの字句位置一覧(&行一覧).iter().map(|位置| 位置.区分).collect();
    let (直下, マクロ, 局所) = (字句位置の区分::モジュールの直下, 字句位置の区分::マクロの呼び出しの中, 字句位置の区分::局所の位置);
    assert_eq!(区分一覧, [直下, マクロ, 局所, 局所, マクロ, マクロ, 直下, 局所, 局所, 直下, 局所, 局所, 局所, 局所, 直下, マクロ, マクロ]);
}
