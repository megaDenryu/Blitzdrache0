//! ファイルの行ごとに、その行の頭の字句位置(位置のモジュールと、その行を囲む波括弧の区分)を求める `モジュールパス` の工程。
//! `module_path.rs` の型に属する実装をここへ置くのは、開いている波括弧を数える走査と、その結果から位置を組む工程が1つの関心事だからである。
//! 位置のモジュールとは、ファイルから推定したモジュールパスの下へ、その行を囲む波括弧付きのモジュール(`mod 名 { … }`)の名前を外側から繋いだものである。
//! 行がモジュールの直下にあるとは、その行の頭で開いている波括弧がすべてモジュールの本体であることである。関数・実装・トレイト・`struct` の本体、`const` のブロック、`use` の群、`macro_rules!` の本体の波括弧が1つでも開いていれば、その行は局所の位置にある。
//! モジュールの直下か、マクロの呼び出しの中の項目の位置で波括弧を使って呼んだマクロ(`素通し! { … }`)の本体は、局所とも普通のモジュールの本体とも別の、マクロの呼び出しの中である。
//! そのマクロは中身をモジュールの項目として展開しうるが、検査器はマクロを展開できず、展開した後の項目の名前を知らないためである。局所の波括弧が1つも開いておらず、マクロの呼び出しの波括弧が1つでも開いていれば、その行はマクロの呼び出しの中にある。
//! モジュールの索引とトレイトの宣言の索引は、モジュールの直下の行に書いた `use` と宣言だけを索引に入れる。Rust では局所の `use` と項目はそれを書いた波括弧の内側でしか見えないためである。
//! 数えるのはコードだけの行の波括弧であり、`mod 名 {` の行と `名前! {` の行の最初の `{` だけをそのモジュールの本体とマクロの呼び出しの本体とする。

use super::super::declaration_prefix::{先頭の属性を読み飛ばす, 属性と可視性を読み飛ばす};
use super::super::identifier_boundary::識別子の文字か;
use super::super::line_matching::先頭の識別子;
use super::モジュールパス;

/// その行の頭で開いている波括弧から決まる、行の位置の区分。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 字句位置の区分 {
    モジュールの直下,
    マクロの呼び出しの中, // モジュールの直下で呼んだマクロの本体の中。局所の波括弧は開いていない
    局所の位置,           // 関数・実装・トレイト・`struct` の本体などの波括弧が1つでも開いている
}

/// ソースのある行の頭の字句位置。位置のモジュールと、その行を囲む波括弧の区分の組である。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 行の字句位置 {
    pub モジュール: モジュールパス,
    pub 区分: 字句位置の区分,
}

impl 行の字句位置 {
    pub fn モジュールの直下か(&self) -> bool {
        self.区分 == 字句位置の区分::モジュールの直下
    }

    pub fn マクロの呼び出しの中か(&self) -> bool {
        self.区分 == 字句位置の区分::マクロの呼び出しの中
    }

    pub fn 局所の位置か(&self) -> bool {
        self.区分 == 字句位置の区分::局所の位置
    }
}

// 開いている波括弧1つが何の本体か。
enum 開いた波括弧 {
    モジュールの本体(String),
    マクロの呼び出しの本体,
    局所の本体,
}

impl モジュールパス {
    /// 自分をファイルのモジュールパスとして、そのファイルの行ごとの、その行の頭の字句位置。
    pub fn 行ごとの字句位置一覧(&self, 行一覧: &[String]) -> Vec<行の字句位置> {
        let mut 開いた波括弧一覧: Vec<開いた波括弧> = Vec::new();
        let mut 一覧 = Vec::with_capacity(行一覧.len());
        for 行 in 行一覧 {
            let 位置 = self.開いた波括弧の並びから位置を組む(&開いた波括弧一覧);
            let mut 最初の波括弧 = match (波括弧付きのモジュールの見出しの名前(行), 位置.局所の位置か()) {
                (Some(名前), _) => Some(開いた波括弧::モジュールの本体(名前)),
                (None, false) if 波括弧で呼ぶマクロの見出しか(行) => Some(開いた波括弧::マクロの呼び出しの本体),
                (None, _) => None,
            };
            一覧.push(位置);
            for 文字 in 行.chars() {
                match 文字 {
                    '{' => 開いた波括弧一覧.push(最初の波括弧.take().unwrap_or(開いた波括弧::局所の本体)),
                    '}' => {
                        開いた波括弧一覧.pop();
                    }
                    _ => {}
                }
            }
        }
        一覧
    }

    // 自分をファイルのモジュールパスとして、開いている波括弧の並びから行の頭の字句位置を組む。
    fn 開いた波括弧の並びから位置を組む(&self, 開いた波括弧一覧: &[開いた波括弧]) -> 行の字句位置 {
        let 名前一覧: Vec<&str> = 開いた波括弧一覧
            .iter()
            .filter_map(|波括弧| match 波括弧 {
                開いた波括弧::モジュールの本体(名前) => Some(名前.as_str()),
                開いた波括弧::マクロの呼び出しの本体 | 開いた波括弧::局所の本体 => None,
            })
            .collect();
        let 区分 = if 開いた波括弧一覧.iter().any(|波括弧| matches!(波括弧, 開いた波括弧::局所の本体)) {
            字句位置の区分::局所の位置
        } else if 開いた波括弧一覧.iter().any(|波括弧| matches!(波括弧, 開いた波括弧::マクロの呼び出しの本体)) {
            字句位置の区分::マクロの呼び出しの中
        } else {
            字句位置の区分::モジュールの直下
        };
        行の字句位置 {
            モジュール: self.下へ繋ぐ(&名前一覧), 区分
        }
    }
}

// `mod 名 {` の行(前に同じ行の属性と可視性があってもよい)なら、そのモジュールの名前。
fn 波括弧付きのモジュールの見出しの名前(行: &str) -> Option<String> {
    let 後ろ = 属性と可視性を読み飛ばす(行).strip_prefix("mod ")?.trim_start();
    let 名前 = 先頭の識別子(後ろ);
    let 名前の後ろ = 後ろ.get(名前.len()..)?.trim_start();
    (!名前.is_empty() && 名前の後ろ.starts_with('{')).then_some(名前)
}

// 項目の位置で波括弧を使ってマクロを呼ぶ見出しの行(`名前! {`・`a::名前! {`。前に同じ行の属性があってもよい)か。`macro_rules!` はマクロの定義であり呼び出しの本体を展開しないため含めない。
fn 波括弧で呼ぶマクロの見出しか(行: &str) -> bool {
    let 残り = 先頭の属性を読み飛ばす(行);
    let パスの長さ = 残り.char_indices().find(|(_, 文字)| !(識別子の文字か(*文字) || *文字 == ':')).map_or(残り.len(), |(位置, _)| 位置);
    let パス = 残り.get(..パスの長さ).unwrap_or_default();
    let 名前の後ろ = 残り.get(パスの長さ..).unwrap_or_default();
    let 名前 = パス.rsplit("::").next().unwrap_or_default();
    !先頭の識別子(パス.trim_start_matches(':')).is_empty() && 名前 != "macro_rules" && 名前の後ろ.strip_prefix('!').is_some_and(|後ろ| 後ろ.trim_start().starts_with('{'))
}
