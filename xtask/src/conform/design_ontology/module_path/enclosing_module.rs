//! ファイルの行ごとに、その行の頭の字句位置(位置のモジュールと、モジュールの直下か)を求める `モジュールパス` の工程。
//! `module_path.rs` の型に属する実装をここへ置くのは、開いている波括弧を数える走査と、その結果から位置を組む工程が1つの関心事だからである。
//! 位置のモジュールとは、ファイルから推定したモジュールパスの下へ、その行を囲む波括弧付きのモジュール(`mod 名 { … }`)の名前を外側から繋いだものである。
//! 行がモジュールの直下にあるとは、その行の頭で開いている波括弧がすべてモジュールの本体であることである。関数・実装・トレイト・`struct` の本体、`const` のブロック、`use` の群、マクロの本体の波括弧が1つでも開いていれば、その行は局所の位置にある。
//! モジュールの索引とトレイトの宣言の索引は、モジュールの直下の行に書いた `use` と宣言だけを索引に入れる。Rust では局所の `use` と項目はそれを書いた波括弧の内側でしか見えないためである。
//! 数えるのはコードだけの行の波括弧であり、`mod 名 {` の行の最初の `{` だけをそのモジュールの本体とする。

use super::super::declaration_prefix::属性と可視性を読み飛ばす;
use super::super::line_matching::先頭の識別子;
use super::モジュールパス;

/// ソースのある行の頭の字句位置。位置のモジュールと、その行がモジュールの直下にあるかの組である。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 行の字句位置 {
    pub モジュール: モジュールパス,
    pub モジュールの直下か: bool, // 偽なら、関数などの本体の内側の局所の位置である
}

impl モジュールパス {
    /// 自分をファイルのモジュールパスとして、そのファイルの行ごとの、その行の頭の字句位置。
    pub fn 行ごとの字句位置一覧(&self, 行一覧: &[String]) -> Vec<行の字句位置> {
        let mut 開いた波括弧: Vec<Option<String>> = Vec::new(); // 開いている波括弧ごとの、それを本体に持つモジュールの名前(モジュールの本体でなければ無い)
        let mut 一覧 = Vec::with_capacity(行一覧.len());
        for 行 in 行一覧 {
            let 名前一覧: Vec<&str> = 開いた波括弧.iter().flatten().map(String::as_str).collect();
            一覧.push(行の字句位置 {
                モジュール: self.下へ繋ぐ(&名前一覧),
                モジュールの直下か: 開いた波括弧.iter().all(Option::is_some),
            });
            let mut モジュール名 = 波括弧付きのモジュールの見出しの名前(行);
            for 文字 in 行.chars() {
                match 文字 {
                    '{' => 開いた波括弧.push(モジュール名.take()),
                    '}' => {
                        開いた波括弧.pop();
                    }
                    _ => {}
                }
            }
        }
        一覧
    }
}

// `mod 名 {` の行(前に同じ行の属性と可視性があってもよい)なら、そのモジュールの名前。
fn 波括弧付きのモジュールの見出しの名前(行: &str) -> Option<String> {
    let 後ろ = 属性と可視性を読み飛ばす(行).strip_prefix("mod ")?.trim_start();
    let 名前 = 先頭の識別子(後ろ);
    let 名前の後ろ = 後ろ.get(名前.len()..)?.trim_start();
    (!名前.is_empty() && 名前の後ろ.starts_with('{')).then_some(名前)
}

#[cfg(test)]
mod tests {
    use super::super::モジュールパス;

    fn 行一覧(行: &[&str]) -> Vec<String> {
        行.iter().map(|行| (*行).to_string()).collect()
    }

    #[test]
    fn 入れ子のモジュールの名前を外側から繋ぎ関数の本体の波括弧はモジュールに数えない() {
        let 行一覧 = 行一覧(&["mod 丙 {", "    fn f() {", "        let _ = 1;", "    }", "    pub(crate) mod 甲 {", "        pub trait 変更 {}", "    }", "}", "trait 外 {}"]);
        let 表記一覧: Vec<String> = モジュールパス::区切り一覧から組む(&["a", "x"]).行ごとの字句位置一覧(&行一覧).iter().map(|位置| 位置.モジュール.表記().to_string()).collect();
        assert_eq!(表記一覧, ["a::x", "a::x::丙", "a::x::丙", "a::x::丙", "a::x::丙", "a::x::丙::甲", "a::x::丙::甲", "a::x::丙", "a::x"]);
    }

    #[test]
    fn 開いている波括弧がすべてモジュールの本体である行だけがモジュールの直下にある() {
        let 行一覧 = 行一覧(&[
            "use a::b;",
            "fn f() {",
            "    use a::c;",
            "    mod 内 {",
            "        use a::d;",
            "    }",
            "}",
            "mod 外 {",
            "    use a::e;",
            "    impl X {",
            "        type Y = u8;",
            "    }",
            "}",
        ]);
        let 直下か一覧: Vec<bool> = モジュールパス::区切り一覧から組む(&["a"]).行ごとの字句位置一覧(&行一覧).iter().map(|位置| 位置.モジュールの直下か).collect();
        assert_eq!(直下か一覧, [true, true, false, false, false, false, false, true, true, true, false, false, true]);
    }
}
