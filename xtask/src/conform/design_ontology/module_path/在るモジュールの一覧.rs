//! 在るモジュールの一覧とは、走査したソースのファイルから推定したモジュールパスの集まりのことである。
//! 受け取るのは走査したソースの一覧、答えるのはあるモジュールパスが在るかである。
//!
//! この一覧が要るのは、起点の予約語(`crate`・`self`・`super`)の無い `use` のパス(`use 子::型;`)の起点を決めるためである。
//! Rust 2018 のパスでは、その最初の区切りは外部クレートの名前か、`use` を書いたモジュールの子のモジュールの名前であり、どちらかは名前だけでは決まらない。
//! 子のモジュールとして在ればそれからの相対であり、無ければ外部クレートである(両方に当たる書き方は rustc が曖昧として拒む)。
//! 集めるのはファイルから推定したモジュールだけであり、ファイルの中の波括弧付きのモジュール(`mod 名 { … }`)は数えない。
//! その子を起点にした相対の `use` は外部クレートのパスとして組まれ、型の定義の探索は定義が見つからないと答える(黙って別の定義を採らない)。

use std::collections::HashSet;
use std::path::PathBuf;

use super::モジュールパス;

/// 走査したソースのファイルから推定したモジュールパスの集まり。
pub struct 在るモジュールの一覧(HashSet<モジュールパス>);

impl 在るモジュールの一覧 {
    /// 走査したソースの一覧の各ファイルから、そのファイルのモジュールパスを集める。
    pub fn ソース一覧から集める(ソース一覧: &[(PathBuf, Vec<String>)]) -> Self {
        Self(ソース一覧.iter().map(|(パス, _)| モジュールパス::ファイルのパスから求める(パス)).collect())
    }

    /// そのモジュールパスが在るか。
    pub fn 含むか(&self, モジュール: &モジュールパス) -> bool {
        self.0.contains(モジュール)
    }
}

impl モジュールパス {
    /// このモジュールに書かれた `use` のパスを絶対のモジュールパスにする。起点の予約語で始まるパスは `書かれたパスを絶対にする` と同じに組む。
    /// 起点の予約語で始まらないパスは、最初の区切りが自分の子のモジュールとして在れば自分からの相対として組み、無ければ外部クレートのパスとして組む。
    pub fn 書かれたパスを在るモジュールで絶対にする(&self, パス: &str, 在るモジュール: &在るモジュールの一覧) -> Self {
        let 最初の区切り = パス.split("::").next().unwrap_or_default().trim();
        let 起点の予約語か = matches!(最初の区切り, "crate" | "self" | "super");
        if !起点の予約語か && 在るモジュール.含むか(&self.下へ繋ぐ(&[最初の区切り])) {
            return self.書かれたパスを絶対にする(&format!("self::{パス}"));
        }
        self.書かれたパスを絶対にする(パス)
    }
}
