//! 実装の対象の型を、検査している型の定義へ結び付けた結果と、結び付けられなかった理由。結び付ける工程(`implementation_binding.rs`)が返し、
//! 自己変更の検査(`mutable_impl_scan.rs`)が、結び付けられない実装の自己変更の根拠を違反の説明へ書くために読む。

/// 実装の対象の型を検査している型の定義へ結び付けた結果。
pub enum 実装の結び付け {
    検査している型,
    別の型,
    結び付けられない(結び付けられない理由),
}

impl 実装の結び付け {
    /// 候補ごとの結び付けを1つにする。検査している型を指しうる候補が1つでもあれば検査している型、無くても結び付けられない候補があれば結び付けられない、全部が別の型なら別の型である。候補が無ければ無い。
    /// cfg で切り替わる取り込みのように同じ名前の候補が複数あるとき、検査している型を指しうる候補を持つ実装を自己変更の検査から落とさないためである。
    pub fn 候補を合わせる(一覧: impl IntoIterator<Item = Self>) -> Option<Self> {
        一覧.into_iter().reduce(|合わせた, 候補| match (合わせた, 候補) {
            (Self::検査している型, _) | (_, Self::検査している型) => Self::検査している型,
            (Self::結び付けられない(理由), _) | (_, Self::結び付けられない(理由)) => Self::結び付けられない(理由),
            (Self::別の型, Self::別の型) => Self::別の型,
        })
    }
}

/// 対象の型を定義へ結び付けられなかった理由。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 結び付けられない理由 {
    パスの修飾を解けない,
    取り込みを解けない,
    型の別名,
    局所の名前が隠しうる,
}

impl 結び付けられない理由 {
    pub const fn 説明(self) -> &'static str {
        match self {
            Self::パスの修飾を解けない => "パスの修飾が指すモジュールに、定義も1段の取り込みも無い",
            Self::取り込みを解けない => "use の取り込み元に定義も1段の取り込みも無いか、同じクレートで取り込みが無い",
            Self::型の別名 => "use の as か type の別名を通している",
            Self::局所の名前が隠しうる => "関数の本体などの局所の位置の実装が書いた名前を、局所の use か項目が隠しうる",
        }
    }
}
