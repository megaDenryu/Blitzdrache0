//! 宣言された論理のモジュール構造と、対象の物理ファイルから得られる物理のモジュール構造が一致することの検証。
//! 一致を確かめる式は2つである。論理のモジュールパスは宣言元のファイルのモジュールパスへ宣言されたモジュール名を繋いだもの、物理のモジュールパスは対象の物理ファイルから求めたものである。
//! この1つの等式が、モジュール名の不一致(`#[path = "接触.rs"] mod 衝突;`)と、宣言元の置き場と違う前置き(`x.rs` の中の `#[path = "y/接触.rs"] mod 接触;`)の両方を同時に捕まえる。
//! 本体が波括弧の中に在る宣言は対象の物理ファイルを持たないため一致の検査をしない。ただしその宣言へ `#[path]` を付ける形は、Rustがファイルを探す規則が変わるため違反にする。
//! 波括弧の内側に置いた `mod 名前;`(波括弧付きのモジュールの中と関数の中の両方)は、論理のモジュールパスが囲む波括弧の分だけ深くなる。この検査はその深さを読まないため、読めない構文として違反にする。
//! 同じ推定を論理と物理の両辺へ当てて一致させる形を採らないのは、その形では別名付けの見逃しが一致として報告され、検査を通ったことが何も保証しなくなるためである。

use std::path::PathBuf;

use super::super::violation::違反;
use super::module_declaration::{モジュール宣言, 宣言を囲む波括弧, 本体の形, 置き場の指定};
use super::module_declaration_extract::モジュール宣言の抽出;
use super::module_path::モジュールパス;

/// 一致が破れる形。
pub enum 不一致の理由 {
    論理と物理のモジュールパスが違う { 論理: String, 物理: String, 正規形の表記: String },
    波括弧の中の宣言に置き場の指定が付いている,
    波括弧の内側から別のファイルを指している,
    置き場の指定の表記を読めない,
    置き場の指定に対応するmodの宣言が無い,
}

impl 不一致の理由 {
    /// 人が読む1行の説明。
    pub fn 説明(&self) -> String {
        let 頭 = "設計オントロジー: モジュールの宣言";
        match self {
            Self::論理と物理のモジュールパスが違う { 論理, 物理, 正規形の表記 } => {
                format!("{頭}が指す物理のモジュール構造が、宣言された論理のモジュール構造と違います(物理のファイル名と論理のモジュール名を別名にしません)。論理は `{論理}`、物理は `{物理}`、正規形の #[path] は \"{正規形の表記}\"")
            }
            Self::波括弧の中の宣言に置き場の指定が付いている => format!("{頭}が波括弧付き(`mod 名前 {{ ... }}`)であるのに #[path] が付いています(波括弧の中の宣言に置き場の指定は要りません)"),
            Self::波括弧の内側から別のファイルを指している => {
                format!("{頭}が波括弧の内側に置かれたまま別のファイルを指しています。この宣言の論理のモジュールパスは囲む波括弧の分だけ深くなり、この検査はその深さを読めないため受理しません(別のファイルを指す宣言は最上位へ置きます)")
            }
            Self::置き場の指定の表記を読めない => format!("{頭}の #[path] の属性の行に文字列がありません(1行で `#[path = \"名前.rs\"]` と書きます)"),
            Self::置き場の指定に対応するmodの宣言が無い => format!("{頭}の #[path] の属性に mod の宣言が続きません(属性だけを残しません)"),
        }
    }
}

/// 1つのソースのモジュールの宣言すべてについて、論理と物理のモジュール構造の一致を確かめる検査。
pub struct モジュール構造の一致検査 {
    パス: PathBuf,
    抽出: モジュール宣言の抽出,
}

impl モジュール構造の一致検査 {
    pub fn 生成する(パス: PathBuf, 原文: &str) -> Self {
        Self {
            抽出: モジュール宣言の抽出::生成する(パス.clone(), 原文),
            パス,
        }
    }

    pub fn 違反一覧(&self) -> Vec<違反> {
        let 宣言の違反一覧 = self.抽出.宣言一覧().into_iter().filter_map(|宣言| self.不一致の理由(&宣言).map(|理由| self.違反にする(宣言.行番号, &理由)));
        let 孤立した属性の違反一覧 = self.抽出.宣言に結び付かないpath属性の行一覧().into_iter().map(|行番号| self.違反にする(行番号, &不一致の理由::置き場の指定に対応するmodの宣言が無い));
        宣言の違反一覧.chain(孤立した属性の違反一覧).collect()
    }

    fn 違反にする(&self, 行番号: usize, 理由: &不一致の理由) -> 違反 {
        違反::行単位(self.パス.clone(), 行番号, 理由.説明())
    }

    fn 不一致の理由(&self, 宣言: &モジュール宣言) -> Option<不一致の理由> {
        match &宣言.置き場の指定 {
            置き場の指定::属性の表記を読めない => return Some(不一致の理由::置き場の指定の表記を読めない),
            置き場の指定::属性で明示する(_) if 宣言.本体の形 == 本体の形::波括弧の中 => return Some(不一致の理由::波括弧の中の宣言に置き場の指定が付いている),
            置き場の指定::属性で明示する(_) | 置き場の指定::既定の探索に任せる => {}
        }
        if 宣言.本体の形 == 本体の形::別のファイル && 宣言.宣言を囲む波括弧 == 宣言を囲む波括弧::波括弧の中にある {
            return Some(不一致の理由::波括弧の内側から別のファイルを指している);
        }
        let 論理 = 宣言.論理のモジュールパス();
        let 物理 = モジュールパス::ファイルのパスから求める(&宣言.対象の物理ファイル()?);
        (論理 != 物理).then(|| 不一致の理由::論理と物理のモジュールパスが違う {
            論理: 論理.表記().to_string(),
            物理: 物理.表記().to_string(),
            正規形の表記: 宣言.正規形のpath属性の表記(),
        })
    }
}
