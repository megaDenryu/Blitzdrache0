//! 対象の型を決められない実装(全称の実装とマクロの本体の中の実装)のうち、自己変更を与える関数を持つものを除外する台帳。
//! 検査器はそれらを `M不変データ` の型へ結び付けられないため、見つけたものは違反にし、`M不変データ` の型に当たらない理由を書いた行があるものだけを除外する。
//! 台帳に載っているのに該当しなくなった行は違反として報告し、台帳からの削除を強制する(`split_debt.rs`・`line_count_allowance.rs` の「台帳 + 陳腐化検査」と同じ様式)。
//! 参照: `_doc/設計/設計オントロジー.md` 第2節の `M不変データ` の自己変更の禁止。

use std::path::{Path, PathBuf};

use super::super::violation::違反;
use super::unbound_implementation::対象の型を決められない実装;

/// 台帳の1行。見出しは本体を開く `{` の手前までを空白の並びを1つに揃えた表記である。除外する理由にはその実装が `M不変データ` の型に当たらない根拠を書き、陳腐化の違反の文言がそのまま読み手へ返す。
pub struct 台帳の行 {
    pub パス: &'static str,
    pub 見出し: &'static str,
    pub 除外する理由: &'static str,
}

/// 注意: 行を足してよいのは、その実装がどの `M不変データ` の型にも当たらないと示せるときだけである。2026-09-23 に走査範囲を調べた時点で該当する実装は無い。
const 登録済みの行一覧: [台帳の行; 0] = [];

pub struct 対象の型を決められない実装の台帳 {
    行一覧: Vec<台帳の行>,
}

impl 対象の型を決められない実装の台帳 {
    /// 本番の検査が使う、登録済みの行の台帳。
    pub fn 登録済みの台帳() -> Self {
        Self {
            行一覧: Vec::from(登録済みの行一覧)
        }
    }

    /// 試験が行を与えて組む台帳。
    #[cfg(test)]
    pub const fn 行一覧から組む(行一覧: Vec<台帳の行>) -> Self {
        Self { 行一覧 }
    }

    /// 見つけた実装のうち台帳に無いものと、台帳に載っているのに見つからなくなった行を、それぞれ違反にする。
    pub fn 突き合わせる(&self, 検出一覧: &[対象の型を決められない実装]) -> Vec<違反> {
        let mut 違反一覧: Vec<違反> = 検出一覧.iter().filter(|検出| !self.行一覧.iter().any(|行| 行.当たるか(検出))).map(対象の型を決められない実装::違反にする).collect();
        違反一覧.extend(self.行一覧.iter().filter(|行| !検出一覧.iter().any(|検出| 行.当たるか(検出))).map(台帳の行::陳腐化の違反));
        違反一覧
    }
}

impl 台帳の行 {
    fn 当たるか(&self, 検出: &対象の型を決められない実装) -> bool {
        台帳の表記へ揃える(&検出.パス) == self.パス && 検出.見出し == self.見出し
    }

    fn 陳腐化の違反(&self) -> 違反 {
        let 説明 = format!(
            "設計オントロジー: 対象の型を決められない実装の台帳に載っている `{}` が、自己変更を与える関数を持つ実装として見つからない(台帳から削除する。載せた理由は「{}」)",
            self.見出し, self.除外する理由
        );
        違反::ファイル単位(PathBuf::from(self.パス), 説明)
    }
}

// 走査で得るパスの区切り文字は実行環境で変わるため、斜線へ揃えてから台帳と照合する。
fn 台帳の表記へ揃える(パス: &Path) -> String {
    パス.to_string_lossy().replace('\\', "/")
}
