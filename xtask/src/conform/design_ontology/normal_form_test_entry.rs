//! 正規形の説明関数を連ねる試験の入口。原文からコードだけの行の一覧と字句の木の一覧の2つを、本番の入口(`scan_entry.rs`)と同じ作り方で作ってから説明関数へ通す。
//! 他の試験の入口(`tests.rs`)と分けるのは、字句の木の門番が原文を要り、コードだけの行の一覧からは作れないためである。

use std::path::{Path, PathBuf};

use super::super::source_lexing::コードだけの行一覧;
use super::impl_syntax::名前で読めない実装の対象の違反一覧;
use super::syntax_checker::クレート構文検査;
use super::token_tree_gate::{予約語でない名前の生の識別子の違反一覧, 型引数の属性の違反一覧, 外部クレートの宣言の違反一覧, 字句の木の一覧};
use super::whitespace_form_assertion::コードの空白の違反一覧;

/// 原文のまま持つソースの断片。字句の木の一覧を要る正規形の入口が、コードだけの行の一覧と字句の木の一覧の2つを本番の入口(`scan_entry.rs`)と同じ原文から作るために使う。
pub(super) fn 原文(名前: &str, 内容: &str) -> (PathBuf, String) {
    (Path::new(名前).to_path_buf(), 内容.to_string())
}

/// 正規形の説明関数だけを連ねた違反の説明の一覧。正規形の検査は、`use … as` の別名を意図して置く他の試験のソースの断片に当たるため、`tests.rs` の全部の説明関数を連ねる入口へ混ぜず、この専用の入口で確かめる。
/// 走査範囲の外のトレイトの台帳の検査も同じ理由でその入口へ混ぜない(他の試験の断片が `impl std::fmt::Display for 規則` のように走査範囲の外のトレイトを実装するためである)。その検査は `external_trait_ledger_tests.rs` が専用の入口で確かめる。
/// 走査範囲の本番の入口(`scan_entry.rs`)は、これらを全部連ねて走らせる。
pub(super) fn 正規形の説明関数を連ねた違反の説明一覧(原文一覧: Vec<(PathBuf, String)>) -> Vec<String> {
    let mut 字句の木 = 字句の木の一覧::default();
    let mut ソース一覧 = Vec::new();
    for (パス, 内容) in 原文一覧 {
        字句の木.原文を数えて足す(パス.clone(), &内容);
        ソース一覧.push((パス, コードだけの行一覧(&内容)));
    }
    let 空白の違反一覧 = コードの空白の違反一覧(&ソース一覧);
    let 実装の対象の違反一覧 = 名前で読めない実装の対象の違反一覧(&ソース一覧);
    let 違反一覧 = クレート構文検査::生成する(ソース一覧)
        .型の表記が名前で追える形であること()
        .includeを呼んでいないこと()
        .取り込みの別名が宣言の名前を名乗っていないこと()
        .読み切れない宣言が無いこと(&字句の木)
        .違反一覧();
    let 字句の木の違反一覧 = 予約語でない名前の生の識別子の違反一覧(&字句の木).into_iter().chain(外部クレートの宣言の違反一覧(&字句の木)).chain(型引数の属性の違反一覧(&字句の木));
    違反一覧.into_iter().chain(字句の木の違反一覧).chain(空白の違反一覧).chain(実装の対象の違反一覧).map(|違反| 違反.説明).collect()
}
