//! 関数の署名の境界の可変の借用を与えるトレイトの型引数に閉じた名前が現れる関数を探す問い。受け取るのは読んだ実装と実装の種類とトレイトの宣言の索引と名前の辺一覧、返すのは自己変更の根拠である。
//! 実装の見出しに名前が当たらない実装でも、関数の署名の境界(`function_signature/signature_bounds.rs`)の可変の借用を与えるトレイトの型引数にマーカーの型の名前が現れれば、その関数はマーカーの型の値を書き換えうる(`impl<T> 変更<T> for Vec<T> { fn 変える(&mut self) where T: DerefMut<Target = 規則> { self[0].0 = 1; } }`)。
//! そのため検査器は、走査範囲のすべての実装について、本体の直下の関数と、実装したトレイトの走査範囲の宣言の関数の署名の境界を照らす。本体の直下のマクロの呼び出しは、見出しに名前が当たった実装だけを根拠にするため、この問いは数えない。
//! 名前を可変の借用を与えるトレイトの型引数の中だけで照らすのは、`impl Extend<地点> for 経路 { fn extend<I: IntoIterator<Item = 地点>>(&mut self, 列: I) }` のような std のトレイトの実装の境界が、値を受け取るだけで `地点` を書き換えないためである。

use super::super::function_signature::{本体の直下の関数の署名一覧, 関数の署名の境界};
use super::super::impl_syntax::実装の種類;
use super::super::line_matching::パスの最後の名前;
use super::super::marker_name_closure::名前の言い換えの辺一覧;
use super::super::read_implementation::読んだ実装;
use super::super::self_modification_evidence::{名前が当たった場所, 自己変更の根拠};
use super::super::trait_declaration_index::トレイトの宣言の索引;

/// 関数の署名の境界で照らす閉じた名前の集合。
pub struct 署名の境界で名前を問う対象<'a> {
    pub 名前の集合: &'a [String],
}

impl 署名の境界で名前を問う対象<'_> {
    /// 実装の本体の直下の関数か、実装したトレイトの宣言の関数の署名の境界の可変の借用を与えるトレイトの型引数に閉じた名前が現れるなら、その根拠。
    pub fn 実装の中の根拠(&self, 実装: &読んだ実装, 種類: &実装の種類, 索引: &トレイトの宣言の索引, 辺一覧: &名前の言い換えの辺一覧) -> Option<自己変更の根拠> {
        let (パス, 行番号) = (実装.パス.to_path_buf(), 実装.行番号);
        let 本体 = 実装.見出し.本体の文字列(実装.行一覧);
        if let Some((対象の名前, 関数名)) = 本体の直下の関数の署名一覧(&本体).into_iter().find_map(|関数| self.指す名前(&関数.境界).map(|名前| (名前, 関数.名前))) {
            return Some(自己変更の根拠::実装の関数 {
                パス,
                行番号,
                対象の名前,
                当たった場所: 名前が当たった場所::関数の署名の境界,
                関数名,
            });
        }
        let 実装の種類::トレイトの実装 { トレイトの表記 } = 種類 else {
            return None;
        };
        let トレイトの名前の集合 = 辺一覧.閉包(パスの最後の名前(トレイトの表記));
        索引.名前で引いた関数一覧(&トレイトの名前の集合).find_map(|引いた関数| {
            self.指す名前(&引いた関数.関数.境界).map(|対象の名前| 自己変更の根拠::トレイトの宣言の関数 {
                パス: パス.clone(),
                行番号,
                対象の名前,
                当たった場所: 名前が当たった場所::関数の署名の境界,
                トレイト名: 引いた関数.トレイト名.to_string(),
                関数名: 引いた関数.関数.名前.clone(),
                同名の宣言の件数: 引いた関数.同名の宣言の件数,
            })
        })
    }

    // 関数の署名の境界の可変の借用を与えるトレイトの型引数が指す、閉じた名前の最初の1つ。
    fn 指す名前(&self, 境界: &関数の署名の境界) -> Option<String> {
        self.名前の集合.iter().find(|名前| 境界.可変の借用で名前を指すか(名前)).cloned()
    }
}
