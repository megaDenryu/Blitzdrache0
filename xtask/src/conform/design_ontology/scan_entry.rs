//! 設計オントロジーの構文検査の入口。走査範囲のソースを1度だけ読み、モジュール構造の一致検査と `クレート構文検査` の説明関数の並びへ通す。
//! 原文からはコードだけの行の一覧を作る。原文そのものは検査へ渡さない。
//! 受け取るのは無し、返すのは違反と警告の報告か、ソースを読めなかった理由である。警告は、設計解釈マーカーを実装した型の実装が定義のファイルの外にあることの1つだけである(`marker_impl_placement.rs`)。検査する規則の全体と保証範囲は親のモジュール `design_ontology.rs` の冒頭が書く。
//! Graphiteの生成物の中の実装にはその警告を出さない。生成物はGraphiteの固定の語彙を展開したものであり、書き手が手で実装を書く場所でないためである(2026-09-26。Issue #187)。
//! 生成物も構文検査の走査には入れる。外すと、生成物が定義する型を名指す手書きの実装が、定義を見つけられない違反へ変わるためである。

use std::path::{Component, Path, PathBuf};

use super::super::error::規約検査の破れ;
use super::super::graphiteのコード::{Graphiteの生成物の一覧, 対象外にした生成物};
use super::super::report::検査の報告;
use super::super::source_lexing::コードだけの行一覧;
use super::module_structure_assertion::モジュール構造の一致検査;
use super::syntax_checker::クレート構文検査;
use crate::file_scan;

/// Graphiteの生成物から外す警告の名前。報告の行がこの名前で外した検査を名乗る。
const 生成物から外す警告: &str = "設計解釈マーカーの実装の置き場の警告";

pub fn 全ファイルを検査する() -> Result<検査の報告, 規約検査の破れ> {
    let mut 原文一覧 = Vec::new();
    for パス in file_scan::対象ファイル一覧を集める(&["crates"], &["rs"])?.into_iter().filter(|パス| srcの下か(パス)) {
        let 内容 = std::fs::read_to_string(&パス).map_err(|誤り| 規約検査の破れ::ファイルを読めなかった(&パス, 誤り))?;
        原文一覧.push((パス, 内容));
    }
    Ok(原文一覧を検査する(原文一覧))
}

/// 読み終えた原文の一覧を検査する。ファイルを読む境界から分けるのは、試験が原文を組んで同じ工程を通すためである。
pub(super) fn 原文一覧を検査する(原文一覧: Vec<(PathBuf, String)>) -> 検査の報告 {
    let 生成物 = Graphiteの生成物の一覧::原文一覧から見分ける(&原文一覧);
    let mut モジュール構造の違反一覧 = Vec::new();
    let mut ソース一覧 = Vec::new();
    for (パス, 内容) in 原文一覧 {
        モジュール構造の違反一覧.extend(モジュール構造の一致検査::生成する(パス.clone(), &内容).違反一覧());
        ソース一覧.push((パス, コードだけの行一覧(&内容)));
    }
    let 検査 = クレート構文検査::生成する(ソース一覧);
    let mut 警告一覧 = 検査.設計解釈マーカーを実装した型の定義のファイルの外にある実装の警告一覧();
    警告一覧.retain(|警告| !生成物.生成物か(&警告.パス));
    let mut 違反一覧 = 検査
        .すべてのコマンドが列挙型であること()
        .すべての規則が構造体であること()
        .すべての結果が列挙型であること()
        .すべての純粋データが参照と内部可変性を持たないこと()
        .すべての引数オブジェクトが任意の値を持たないこと()
        .排他の分類を同時に名乗っていないこと()
        .設計解釈マーカーを別名で取り込んでいないこと()
        .設計解釈マーカーの実装が正規形であること()
        .設計解釈マーカーを再公開していないこと()
        .設計解釈マーカーの実装が波括弧付きのモジュールの中に無いこと()
        .違反一覧();
    違反一覧.extend(モジュール構造の違反一覧);
    let 外した生成物 = 対象外にした生成物::生成する(生成物から外す警告, 生成物.生成物一覧().to_vec());
    検査の報告::生成する(違反一覧, 警告一覧).対象外にした生成物を足す(外した生成物)
}

fn srcの下か(パス: &Path) -> bool {
    パス.components().any(|部品| matches!(部品, Component::Normal(名前) if 名前 == "src"))
}
