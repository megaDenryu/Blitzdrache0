//! 名前の言い換えの辺の一覧と、1つの名前から辺をたどって閉じた名前の並び。全ソースから1度だけ組み、受け取るのは種の名前、返すのは閉じた名前の並びである。
//! 閉包は2段で求める。第1段は同じ型を指す名前の集合であり、辺は `use …::元 as 別名;` の別名と元の名前(双方向)、項目の `type 別名 = 右辺;` の別名と右辺のパスの最後の名前(双方向)、
//! 実装の本体の直下の関連型の宣言 `type 名前 = 右辺;` の右辺のパスの最後の名前から関連型の名前(片方向)である。双方向にするのは、マーカーを別名の側へ書く形(`type 別名 = 規則; impl M不変データ for 別名`)で本体の型名 `規則` が漏れるためである。
//! 関連型を片方向にするのは、関連型の名前が射影(`<甲 as 領域>::状態`)を通して右辺の型を指しうる一方、同じ名前の関連型が実装ごとに別の型を指し、関連型の名前から右辺へ辿ると無関係な型どうしが繋がるためである。
//! 関連型を辺から外さないのは、射影を型引数の中に書いた実装(`impl 変更 for Vec<<甲 as 領域>::状態>`)と別名(`type 包み<T> = Vec<<T as 領域>::状態>;`)が、字面に右辺の型の名前を持たずに右辺の型の値を書き換えうるためである。
//! 第2段は、第1段の集合の型を包む名前の集合である。辺は、右辺に第1段か第2段の集合の名前を識別子の境界で含む型の別名(関連型を含む)への片方向と、`use` の別名の双方向である。第2段の名前からは右辺の最後の名前(`Vec`・`fn`)へ辿らない。
//! 辿ると、包む型の名前を通して同じ型を包む無関係な別名が連鎖して閉包へ入るためである。2段とも辺を足しても減らない集合の最小の不動点であるため、結果は辿る順序によらない。
//! 並びを辞書順で返すのは、同じ入力から常に同じ違反の説明が出るようにするためである。

use std::collections::{BTreeSet, HashMap};
use std::path::PathBuf;

use super::identifier_boundary::識別子として現れるか;
use super::impl_body_direct_lines::実装の本体の直下の行一覧;
use super::line_matching::パスの最後の名前;
use super::type_alias_scan::{型の別名の宣言, 型の別名の宣言を読む};
use super::use_resolution::書き出しの行付きの取り込みの項目一覧;

// 名前ごとに、辺でたどる相手の名前の一覧を持つ表。
#[derive(Default)]
struct 相手の表(HashMap<String, Vec<String>>);

impl 相手の表 {
    // 名前の相手へ1つ足す。どちらかが空か、2つが同じか、既に在るなら足さない。
    fn 足す(&mut self, 名前: &str, 相手: &str) {
        if 名前.is_empty() || 相手.is_empty() || 名前 == 相手 {
            return;
        }
        let 一覧 = self.0.entry(名前.to_string()).or_default();
        if !一覧.iter().any(|登録済み| 登録済み == 相手) {
            一覧.push(相手.to_string());
        }
    }

    fn 相手(&self, 名前: &str) -> impl Iterator<Item = &String> {
        self.0.get(名前).into_iter().flatten()
    }
}

#[derive(Default)]
pub struct 名前の言い換えの辺一覧 {
    取り込みの相手: 相手の表,                // 第1段と第2段の双方向の辺
    同じ型の相手: 相手の表,                  // 第1段だけの辺。項目の型の別名は双方向、関連型は片方向
    型の別名の宣言一覧: Vec<型の別名の宣言>, // 第2段の包む辺の材料。関連型を含む
}

impl 名前の言い換えの辺一覧 {
    pub fn 全ソースから組む(ソース一覧: &[(PathBuf, Vec<String>)]) -> Self {
        let mut 辺一覧 = Self::default();
        for (_, 行一覧) in ソース一覧 {
            let 実装の本体の直下 = 実装の本体の直下の行一覧::ファイルから集める(行一覧);
            for 添字 in 0..行一覧.len() {
                if let Some(宣言) = 型の別名の宣言を読む(行一覧, 添字).読めた値() {
                    let 右辺の名前 = パスの最後の名前(&宣言.右辺).to_string();
                    辺一覧.同じ型の相手.足す(&右辺の名前, &宣言.別名);
                    if !実装の本体の直下.含むか(添字) {
                        辺一覧.同じ型の相手.足す(&宣言.別名, &右辺の名前);
                    }
                    辺一覧.型の別名の宣言一覧.push(宣言);
                }
            }
            for 在り処 in 書き出しの行付きの取り込みの項目一覧(行一覧).項目一覧 {
                if let Some(別名) = 在り処.項目.別名.as_deref() {
                    辺一覧.取り込みの相手.足す(別名, 在り処.項目.元の名前());
                    辺一覧.取り込みの相手.足す(在り処.項目.元の名前(), 別名);
                }
            }
        }
        辺一覧
    }

    /// 種の名前から第1段と第2段の辺をたどって閉じた名前の並び。種そのものを必ず含み、並びは辞書順である。
    pub fn 閉包(&self, 種: &str) -> Vec<String> {
        let mut 集合 = BTreeSet::from([種.to_string()]);
        self.閉じるまで足す(&mut 集合, |名前| self.取り込みの相手.相手(名前).chain(self.同じ型の相手.相手(名前)).collect());
        self.閉じるまで足す(&mut 集合, |名前| self.取り込みの相手.相手(名前).chain(self.包む別名(名前)).collect());
        集合.into_iter().collect()
    }

    // 集合のすべての名前から始めて、相手の名前を集合へ足すことを変化が止まるまで繰り返す。
    fn 閉じるまで足す<'a>(&'a self, 集合: &mut BTreeSet<String>, 相手を並べる: impl Fn(&str) -> Vec<&'a String>) {
        let mut 未処理: Vec<String> = 集合.iter().cloned().collect();
        while let Some(名前) = 未処理.pop() {
            for 相手 in 相手を並べる(&名前) {
                if 集合.insert(相手.clone()) {
                    未処理.push(相手.clone());
                }
            }
        }
    }

    // 右辺にその名前を識別子の境界で含む型の別名の名前。
    fn 包む別名(&self, 名前: &str) -> impl Iterator<Item = &String> {
        self.型の別名の宣言一覧.iter().filter(move |宣言| 識別子として現れるか(&宣言.右辺, 名前)).map(|宣言| &宣言.別名)
    }
}
