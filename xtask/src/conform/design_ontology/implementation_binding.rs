//! 実装の対象の型の表記を、検査している型の定義へ結び付ける工程。受け取るのは読んだ実装とその対象の型と検査する型の定義とモジュールの索引、返すのは結び付けた結果である。
//! 型の同一性は定義のモジュールパス + 型名である。名前が一致する実装は次の順で結び付ける。パスの修飾があれば、修飾が指しうるモジュールで定義を探す。
//! 修飾が無ければ、実装と定義が同じファイルなら検査している型、実装のファイルが同名の型を定義していれば別の型とし、明示の `use` があればその取り込み元で、無ければ glob の取り込み(`use super::*;`)の取り込み元で定義を探す。
//! 取り込み元のモジュールが定義を持たなければ、そのモジュールの `use`(再公開の `pub use` を含む。子のモジュールは親の非公開の取り込みも使える)を1段たどる。候補とその1段の探し方は、トレイトの宣言を引く工程と共有する(`module_index/name_location_search.rs`)。
//! どこでも定義を見つけられない実装は、黙って外さず結び付けられない実装にする。ただし修飾も取り込みも無い実装は、定義と別のクレートにあり、定義のクレートを glob で取り込んでもいなければ別の型とする。
//! 別のクレートの型は、取り込むかパスで書かなければ名指せないためである。
//! 名前が違っても、`use 元 as 名前`(このファイルか、明示の取り込みか glob の取り込みの取り込み元のモジュールで1段)か、走査範囲のどこかの `type 名前 = 元;` で型名を指す実装は、別名を通した結び付けられない実装にする。
//! 2段以上の再公開と glob を重ねた別名は、名前が違うため別の型として外す(保証範囲の外。正本 `_doc/設計/設計オントロジー.md` 2.5.3)。

use super::binding_outcome::{実装の結び付け, 結び付けられない理由};
use super::impl_syntax::実装の対象の型;
use super::module_index::name_location_search::{修飾の無い名前の在り処, 名前の在り処, 名前の在り処の探索};
use super::module_index::{モジュールの索引, 行一覧が型を定義しているか};
use super::module_path::モジュールパス;
use super::mutable_impl_scan::検査する型の定義;
use super::read_implementation::読んだ実装;

// 型名を宣言したモジュールの在り処を、検査している型の定義のモジュールと突き合わせた結び付け。見つからないか深さを超えたなら無い(呼び出し側が理由を決める)。
fn 在り処から結び付ける(在り処: &名前の在り処, 定義のモジュール: &モジュールパス) -> Option<実装の結び付け> {
    match 在り処 {
        名前の在り処::見つかった(一覧) if 一覧.contains(定義のモジュール) => Some(実装の結び付け::検査している型),
        名前の在り処::見つかった(_) => Some(実装の結び付け::別の型),
        名前の在り処::別名を通している => Some(実装の結び付け::結び付けられない(結び付けられない理由::型の別名)),
        名前の在り処::深さを超えた(_) | 名前の在り処::見つからない => None,
    }
}

impl 読んだ実装<'_> {
    /// 対象の型を、検査している型の定義へ結び付ける。全称の実装(対象が型引数)は呼び出し側が除く。
    pub fn 対象の型を結び付ける(&self, 索引: &モジュールの索引<'_>, 対象: &実装の対象の型, 型: &検査する型の定義) -> 実装の結び付け {
        let 自分 = モジュールパス::ファイルのパスから求める(self.パス);
        if 対象.名前() != 型.型名 {
            let 型の別名か = 索引.型の別名の表().別名が型名を指しうるか(対象.名前(), 型.型名);
            return if 型の別名か || self.別名の元の名前(索引, 対象.パスの修飾(), 対象.名前()) == Some(型.型名) {
                実装の結び付け::結び付けられない(結び付けられない理由::型の別名)
            } else {
                実装の結び付け::別の型
            };
        }
        let 探索 = 名前の在り処の探索 {
            索引,
            名前: 型.型名,
            宣言しているか: |モジュール: &モジュールパス| 索引.型を定義しているか(モジュール, 型.型名),
        };
        let 定義のモジュール = モジュールパス::ファイルのパスから求める(型.定義のパス);
        match 対象.パスの修飾() {
            Some(修飾) => 在り処から結び付ける(&探索.候補から探す(&自分.書かれたパスが指しうるモジュール一覧(修飾)), &定義のモジュール).unwrap_or(実装の結び付け::結び付けられない(結び付けられない理由::パスの修飾を解けない)),
            None => self.修飾の無い対象を結び付ける(&探索, 型, &定義のモジュール, &自分),
        }
    }

    // 修飾の無い対象の型を、同じファイルの定義・明示の取り込み・glob の取り込みの順で結び付ける。
    fn 修飾の無い対象を結び付ける<F: Fn(&モジュールパス) -> bool>(
        &self, 探索: &名前の在り処の探索<'_, F>, 型: &検査する型の定義, 定義のモジュール: &モジュールパス, 自分: &モジュールパス
    ) -> 実装の結び付け {
        if self.パス == 型.定義のパス {
            return 実装の結び付け::検査している型;
        }
        if 行一覧が型を定義しているか(self.行一覧, 型.型名) {
            return 実装の結び付け::別の型;
        }
        match 探索.修飾の無い名前を取り込みから探す(自分) {
            修飾の無い名前の在り処::別名を通している => return 実装の結び付け::結び付けられない(結び付けられない理由::型の別名),
            修飾の無い名前の在り処::明示の取り込みから(在り処) => {
                return 在り処から結び付ける(&在り処, 定義のモジュール).unwrap_or(実装の結び付け::結び付けられない(結び付けられない理由::取り込みを解けない));
            }
            修飾の無い名前の在り処::名前を全部取り込む取り込みから(在り処) => {
                if let Some(結び付け) = 在り処から結び付ける(&在り処, 定義のモジュール) {
                    return 結び付け;
                }
            }
            修飾の無い名前の在り処::取り込んでいない => {}
        }
        let glob一覧: Vec<[モジュールパス; 2]> = 探索
            .索引
            .取り込みの項目一覧(自分)
            .iter()
            .filter(|項目| 項目.全部を取り込むか())
            .map(|項目| 自分.書かれたパスが指しうるモジュール一覧(項目.親のパス()))
            .collect();
        let 定義のクレート = 定義のモジュール.クレート();
        if 自分.クレート() == 定義のクレート || glob一覧.iter().flatten().any(|モジュール| モジュール.クレート() == 定義のクレート) {
            実装の結び付け::結び付けられない(結び付けられない理由::取り込みを解けない)
        } else {
            実装の結び付け::別の型
        }
    }
}
