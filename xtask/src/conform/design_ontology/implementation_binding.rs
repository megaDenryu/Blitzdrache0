//! 実装の対象の型の表記を、検査している型の定義へ結び付ける工程。受け取るのは読んだ実装とその対象の型と検査する型の定義とモジュールの索引、返すのは結び付けた結果である。
//! 型の同一性は定義の位置のモジュール(定義のファイルのモジュールパス + 定義の行を囲む `mod 名 { … }` の並び)+ 型名である。同じファイルの `mod 内 { struct 規則; }` とファイルの直下の `struct 規則;` は別の型であり、ファイルが同じことを同じ型の根拠にしない。
//! 名前が一致する実装は次の順で結び付ける。パスの修飾があれば、修飾が指しうるモジュールで定義を探す。
//! 修飾が無ければ、実装の位置のモジュールの直下が同名の型を定義していれば、そのモジュールが定義の位置のモジュールなら検査している型、違えば別の型とし、明示の `use` の全部の取り込み元と、明示の `use` と宣言に隠されない glob の取り込み(`use super::*;`)の取り込み元で定義を探す。
//! 同じ名前の候補が複数ある(cfg で切り替わる取り込み)ときは1つに決めず、どれか1つでも検査している型を指しうれば検査している型にする(`binding_outcome.rs` の候補を合わせる規則)。
//! 修飾と `use` は、実装の位置のモジュール(囲む `mod 名 { … }` を繋いだもの)から解き、そのモジュールの直下に書いた `use` と定義だけを使う。波括弧付きのモジュールは親の `use` を引き継がず、関数の本体などの局所の `use` と定義はその本体の内側でしか見えないためである。
//! 局所の位置に書いた実装は、局所の `use` か項目が書いた名前(修飾があればその起点)を隠しうるなら結び付けられない実装にし、局所の `use … as` か `type` の別名が型名を指しうるなら別名を通した結び付けられない実装にする。
//! 実装の位置のモジュールで波括弧を使って呼んだマクロの本体(マクロの呼び出しの中)の `use` か項目が、書いた名前(修飾があればその起点)を隠しうるか、その `use … as` か `type` の別名が型名を指しうるなら、どの位置の実装も結び付けられない実装にする。
//! 取り込み元のモジュールが定義を持たなければ、そのモジュールの `use`(再公開の `pub use` を含む。子のモジュールは親の非公開の取り込みも使える)を1段たどる。候補とその1段の探し方は、トレイトの宣言を引く工程と共有する(`module_index/name_location_search.rs`)。
//! どこでも定義を見つけられない実装は、黙って外さず結び付けられない実装にする。ただし修飾も取り込みも無い実装は、定義と別のクレートにあり、定義のクレートを glob で取り込んでもいなければ別の型とする。
//! 別のクレートの型は、取り込むかパスで書かなければ名指せないためである。
//! 名前が違っても、`use 元 as 名前`(このファイルか、明示の取り込みか glob の取り込みの取り込み元のモジュールで1段)か、走査範囲のどこかの `type 名前 = 元;` で型名を指す実装は、別名を通した結び付けられない実装にする。
//! 2段以上の再公開と glob を重ねた別名は、名前が違うため別の型として外す(保証範囲の外。正本 `_doc/設計/設計オントロジー.md` 2.5.3)。

use super::binding_outcome::{実装の結び付け, 結び付けられない理由};
use super::impl_syntax::実装の対象の型;
use super::module_index::name_location::名前の在り処;
use super::module_index::name_location_search::名前の在り処の探索;
use super::module_index::モジュールの索引;
use super::module_path::モジュールパス;
use super::mutable_impl_scan::検査する型の定義;
use super::read_implementation::読んだ実装;

// 型名の在り処を、検査している型の定義のモジュールと突き合わせた結び付け。定義のモジュールを宣言の中に含めば検査している型、別名を通していれば型の別名である。
// たどり切れなかった取り込みがあるか、見つからなければ無い(呼び出し側が理由を決める)。それ以外で宣言があれば別の型である。
fn 在り処から結び付ける(在り処: &名前の在り処, 定義のモジュール: &モジュールパス) -> Option<実装の結び付け> {
    if 在り処.宣言したモジュール一覧.contains(定義のモジュール) {
        return Some(実装の結び付け::検査している型);
    }
    if 在り処.別名を通しているか {
        return Some(実装の結び付け::結び付けられない(結び付けられない理由::型の別名));
    }
    (在り処.たどり切れなかったモジュール一覧.is_empty() && !在り処.宣言したモジュール一覧.is_empty()).then_some(実装の結び付け::別の型)
}

impl 読んだ実装<'_> {
    /// 対象の型を、検査している型の定義へ結び付ける。全称の実装(対象が型引数)は呼び出し側が除く。
    pub fn 対象の型を結び付ける(&self, 索引: &モジュールの索引, 対象: &実装の対象の型, 型: &検査する型の定義) -> 実装の結び付け {
        if 対象.名前() != 型.型名 {
            if self.マクロの呼び出しの中の別名が型名を指しうるか(索引, 対象.名前(), 型.型名) {
                return 実装の結び付け::結び付けられない(結び付けられない理由::マクロの呼び出しの中の名前が隠しうる);
            }
            let 型の別名か = 索引.型の別名の表().別名が型名を指しうるか(対象.名前(), 型.型名) || self.局所の別名が型名を指しうるか(索引, 対象.名前(), 型.型名);
            return if 型の別名か || self.別名の元の名前一覧(索引, 対象.パスの修飾(), 対象.名前()).contains(&型.型名) {
                実装の結び付け::結び付けられない(結び付けられない理由::型の別名)
            } else {
                実装の結び付け::別の型
            };
        }
        let 起点 = 対象.パスの修飾().map_or(対象.名前(), |修飾| 修飾.split("::").next().unwrap_or_default().trim());
        if self.局所の名前が隠しうるか(索引, 起点) {
            return 実装の結び付け::結び付けられない(結び付けられない理由::局所の名前が隠しうる);
        }
        if self.マクロの呼び出しの中の名前が隠しうるか(索引, 起点) {
            return 実装の結び付け::結び付けられない(結び付けられない理由::マクロの呼び出しの中の名前が隠しうる);
        }
        let 探索 = 名前の在り処の探索 {
            索引,
            名前: 型.型名,
            宣言しているか: |モジュール: &モジュールパス| 索引.型を定義しているか(モジュール, 型.型名),
        };
        let 自分 = self.位置のモジュール(索引);
        match 対象.パスの修飾() {
            Some(修飾) => 在り処から結び付ける(&探索.候補から探す(&自分.書かれたパスが指しうるモジュール一覧(修飾)), 型.定義のモジュール).unwrap_or(実装の結び付け::結び付けられない(結び付けられない理由::パスの修飾を解けない)),
            None => 修飾の無い対象を結び付ける(&探索, 型.定義のモジュール, &自分),
        }
    }
}

// 修飾の無い対象の型を、実装の位置のモジュールの直下の定義・明示の取り込みの全部・glob の取り込みから結び付ける。直下の定義は、実装の位置のモジュールが定義のモジュールなら検査している型、違えば別の型である。
// 候補が複数あれば 実装の結び付け::候補を合わせる で1つにする。どの候補からも結び付かなければ、クレートの境界で決める。
fn 修飾の無い対象を結び付ける<F: Fn(&モジュールパス) -> bool>(探索: &名前の在り処の探索<'_, F>, 定義のモジュール: &モジュールパス, 自分: &モジュールパス) -> 実装の結び付け {
    let 在り処 = 探索.修飾の無い名前を取り込みから探す(自分);
    if 在り処.別名を通しているか {
        return 実装の結び付け::結び付けられない(結び付けられない理由::型の別名);
    }
    let 自分の定義 = 在り処.自分が宣言しているか.then_some(if 自分 == 定義のモジュール {
        実装の結び付け::検査している型
    } else {
        実装の結び付け::別の型
    });
    let 明示の取り込み一覧 = 在り処
        .明示の取り込みごとの在り処
        .iter()
        .map(|在り処| 在り処から結び付ける(在り処, 定義のモジュール).unwrap_or(実装の結び付け::結び付けられない(結び付けられない理由::取り込みを解けない)));
    let glob一覧 = 在り処.globごとの在り処.iter().filter_map(|在り処| 在り処から結び付ける(在り処, 定義のモジュール));
    if let Some(結び付け) = 実装の結び付け::候補を合わせる(自分の定義.into_iter().chain(明示の取り込み一覧).chain(glob一覧)) {
        return 結び付け;
    }
    let glob一覧: Vec<[モジュールパス; 2]> = 探索
        .索引
        .取り込みの項目一覧(自分)
        .iter()
        .filter(|項目| 項目.全部を取り込むか())
        .map(|項目| 自分.書かれたパスが指しうるモジュール一覧(項目.親のパス()))
        .collect();
    let 定義のクレート = 定義のモジュール.クレート();
    if 自分.クレート() == 定義のクレート || glob一覧.iter().flatten().any(|モジュール| モジュール.クレート() == 定義のクレート) {
        実装の結び付け::結び付けられない(結び付けられない理由::取り込みを解けない)
    } else {
        実装の結び付け::別の型
    }
}
