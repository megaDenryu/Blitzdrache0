//! `use` と `type` の宣言を読む工程が共有する結末の型。読む工程は1つの宣言について「その宣言でない」「読めた」「読めない」の3つだけを返し、読み切れない綴りを黙って飛ばさない。
//! `impl` の見出しの読み切れなさ(本体を開く `{` に届かない見出し)と行の頭でない項目の予約語は、`readable_form_assertion.rs` が同じ読めない宣言の在り処として組む。
//! グローバルCLAUDE.md「検査器は解析できなかった入力を黙って対象から外してはならない」が、解析できなかった入力を違反にも件数にもせず読み飛ばすことを禁じるためである。
//! 読み切れない綴りを違反として報告するのは `readable_form_assertion.rs` の1つだけであり、名前の閉包と取り込み元の探索は、その違反が別に出ることを前提にして読めた分だけを使う。

use std::path::{Path, PathBuf};

use super::super::violation::違反;

/// 1つの行(または1つの文)を読んだ結末。
pub enum 宣言を読んだ結末<T> {
    その宣言でない,
    読めた(T),
    読めない(読めない宣言),
}

/// 読み切れなかった宣言1件。読めなかった綴りと、読み切れない理由を持つ。理由は違反の説明がそのまま読み手へ返す。
pub struct 読めない宣言 {
    pub 綴り: String,
    pub 理由: &'static str,
}

/// 1つのファイルの中の、読み切れなかった宣言1件の在り処。行番号は1始まりである。
pub struct 読めない宣言の在り処 {
    pub 行番号: usize,
    pub 宣言: 読めない宣言,
}

impl<T> 宣言を読んだ結末<T> {
    /// 読めた値。その宣言でないときと読み切れないときは無い。
    pub fn 読めた値(self) -> Option<T> {
        match self {
            Self::読めた(値) => Some(値),
            Self::その宣言でない | Self::読めない(_) => None,
        }
    }

    /// 読み切れなかった宣言。読めたときとその宣言でないときは無い。
    pub fn 読めなかった宣言(self) -> Option<読めない宣言> {
        match self {
            Self::読めない(宣言) => Some(宣言),
            Self::その宣言でない | Self::読めた(_) => None,
        }
    }
}

impl 読めない宣言の在り処 {
    /// その1件の違反。読み切れない綴りを黙って飛ばすと、その宣言が持ち込む名前と実装が検査から落ちることを説明に書く。
    pub fn 違反にする(&self, パス: &Path) -> 違反 {
        let 説明 = format!(
            "設計オントロジー: 検査器がこの宣言を読み切れない(`{}`。{})。読み切れない綴りを黙って飛ばすと、その宣言が持ち込む名前と実装が検査から落ちるため違反にする",
            self.宣言.綴り, self.宣言.理由
        );
        違反::行単位(PathBuf::from(パス), self.行番号, 説明)
    }
}
