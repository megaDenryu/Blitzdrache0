//! コードの中の空白を半角空白と改行だけに固定する純粋な工程。受け取るのはファイルごとのコードだけの行の一覧、返すのは書いてはならない空白を持つ行の違反一覧である。
//! 行単位の読み口は、宣言を半角空白の区切りで読む(`impl 初期化 for 規則`)。rustc はタブ・垂直タブ・改ページ・U+0085・U+200E・U+200F・U+2028・U+2029 と、改行の直前でない復帰も空白として読むため、
//! それらで区切った宣言(`impl 初期化 for\t規則 {}`)はコンパイルが通るのに、読み口がトレイトの実装と読まずに検査から落ちる。そのため、この9つをコードの中に書くことを違反にする。
//! 一覧は Rust の参照が空白と定める Unicode の Pattern_White_Space から、半角空白と改行を除いたものである。`char::is_whitespace` は U+200E と U+200F を空白と見なさないため使わない。
//! コメントと文字列と文字の中の空白は、コードだけの行に残らないため対象にならない。復帰改行の復帰はコードだけの行を作るときに改行へ揃っているため、残った復帰は改行の直前でない復帰である。走査範囲の現状は0件である。
//! `クレート構文検査` の説明関数にしないのは、この工程が読むのは行の文字だけであり、型の定義も実装も引かないためである。

use std::path::{Path, PathBuf};

use super::super::violation::違反;

const 書いてはならない空白の一覧: [char; 9] = ['\t', '\u{b}', '\u{c}', '\r', '\u{85}', '\u{200e}', '\u{200f}', '\u{2028}', '\u{2029}'];

/// コードの中に書いてはならない空白を持つ行の違反一覧。並びはファイルの順、ファイルの中では行の順である。
pub fn コードの空白の違反一覧(ソース一覧: &[(PathBuf, Vec<String>)]) -> Vec<違反> {
    ソース一覧
        .iter()
        .flat_map(|(パス, 行一覧)| 行一覧.iter().enumerate().filter_map(move |(添字, 行)| 書いてはならない空白の違反(パス, 添字 + 1, 行)))
        .collect()
}

// その行のコードの中に書いてはならない空白があれば、その違反。空白は符号位置で名指す。
fn 書いてはならない空白の違反(パス: &Path, 行番号: usize, 行: &str) -> Option<違反> {
    let 符号位置一覧: Vec<String> = 書いてはならない空白の一覧.iter().filter(|空白| 行.contains(**空白)).map(|空白| format!("U+{:04X}", u32::from(*空白))).collect();
    if 符号位置一覧.is_empty() {
        return None;
    }
    let 説明 = format!(
        "設計オントロジー: コードの中に半角空白と改行でない空白({})を書いている。rustc はこれを空白として読むが、検査器の読み口は半角空白の区切りで宣言を読むため、この空白で区切った宣言を黙って検査から落とす。半角空白に書き換える",
        符号位置一覧.join("・")
    );
    Some(違反::行単位(パス.to_path_buf(), 行番号, 説明))
}
