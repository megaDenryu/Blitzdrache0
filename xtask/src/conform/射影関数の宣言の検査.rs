//! 射影関数の宣言の検査。射影の型が入力の状態をそのまま、または包み(`Vec`・`Option`・`Box`・`Arc` など)の中に持つ射影関数の宣言(`M射影関数<状態, 状態>`・`M射影関数<状態, Vec<状態>>`)を違反にする。
//! 受け取るのは抽出したもの、返すのは違反一覧である。
//!
//! 射影関数とは、状態から外部向けの別の値を取り出す一方向の観測の計算である(`_doc/設計/設計オントロジー.md` 第3節)。同じ状態を返すか包んで返す射影は定義に反する。
//! しかも定義の式はこの宣言から、同じ処理が状態を変換用の素材にしかつ生成すると導くため、状態の存在理由の公理(A3)が
//! 遷移の宣言と見分けられず、遷移の役割を宣言しないまま公理を通す抜け道になる。
//!
//! 同じ型かは、書いたままの型引数の表記でなく、定義の式がその宣言から導いた変換用の素材にする関係と生成する関係の目的語のノードで比べる。定義の式は射影の型の表記の
//! 包みを剥がして中身の型を生成すると導くため、ノードで比べると、射影の型が状態をそのまま持つ宣言と包みの中に持つ宣言の両方が当たる。表記で比べると後者を見落とす。置き場を構造の法則でなく規約の検査にするのは、
//! 設計関係グラフのエッジがどの役割の宣言から導かれたかを命題の語彙で問えず、宣言の形そのものの規則だからである。

use super::violation::違反;
use crate::設計関係のモデル::{抽出した設計関係グラフと抽出の欠け, 抽出元の構文};
use blitz_design_verification::{関数の引数と戻り値の役目, 関数の役割};

/// 射影関数の宣言のうち、変換用の素材にする状態と、射影の型から生成すると導いた型が同じノードである宣言を違反にする。
pub fn 抽出したものを検査する(抽出したもの: &抽出した設計関係グラフと抽出の欠け) -> Vec<違反> {
    let 関係一覧 = 抽出したもの.グラフ.関係一覧();
    抽出したもの
        .プリミティブな宣言
        .関数の役割の宣言一覧
        .iter()
        .filter(|宣言| 宣言.役割 == 関数の役割::M射影関数)
        .filter(|宣言| {
            let 同じ宣言から導いた関係 = |役目: 関数の引数と戻り値の役目| {
                関係一覧
                    .iter()
                    .filter(move |関係| 関係.結び付き方 == 役目.設計関係の結び付き方へ写す() && 関係.出どころ.構文 == 抽出元の構文::関数の役割の型引数 && 関係.出どころ.パス == 宣言.出どころ.パス && 関係.出どころ.行番号 == 宣言.出どころ.行番号)
            };
            同じ宣言から導いた関係(関数の引数と戻り値の役目::変換用の素材にする).any(|素材| 同じ宣言から導いた関係(関数の引数と戻り値の役目::生成する).any(|生成| 生成.目的語 == 素材.目的語))
        })
        .map(|宣言| {
            違反::行単位(
                宣言.出どころ.パス.clone(),
                宣言.出どころ.行番号,
                "射影関数の射影の型が入力の状態をそのまま、または包みの中に持つ。射影関数は状態から別の値を取り出す関数であり、状態を受けて同じ状態を返す関数は遷移か規則によらない書き換えの役割で宣言する".to_string(),
            )
        })
        .collect()
}
