//! 射影関数の宣言の検査。入力の状態と出力の射影に同じ型を置いた `M射影関数<状態, 状態>` の宣言を違反にする。受け取るのは抽出したもの、返すのは違反一覧である。
//!
//! 射影関数とは、状態から外部向けの別の値を取り出す一方向の観測の計算である(`_doc/設計/設計オントロジー.md` 第3節)。同じ状態を返す射影は定義に反する。
//! しかも定義の式はこの宣言から、同じ処理が状態を消費しかつ生成すると導くため、状態の存在理由の公理(A3)と状態を受けて返す処理の宣言の法則(A7)が
//! 遷移の宣言と見分けられず、遷移の役割を宣言しないまま両方を通す抜け道になる。
//!
//! 同じ型かは、書いたままの型引数の表記でなく、定義の式がその宣言から導いた消費する関係と生成する関係の目的語の節点で比べる。表記で比べると、
//! `M射影関数<状態, crate::a::状態>` のように同じ型を別の書き方で書いた宣言を見落とすためである。置き場を構造の法則でなく規約の検査にするのは、
//! 設計関係グラフの辺がどの役割の宣言から導かれたかを命題の語彙で問えず、宣言の形そのものの規則だからである。

use super::violation::違反;
use crate::設計関係のモデル::{抽出した設計関係グラフと抽出の欠け, 抽出元の構文, 設計関係の種類};
use blitz_design_verification::関数の役割;

/// 射影関数の宣言のうち、消費する状態と生成する射影が同じ節点である宣言を違反にする。
pub fn 抽出したものを検査する(抽出したもの: &抽出した設計関係グラフと抽出の欠け) -> Vec<違反> {
    let 関係一覧 = 抽出したもの.グラフ.関係一覧();
    抽出したもの
        .事実
        .関数の役割の宣言一覧
        .iter()
        .filter(|宣言| 宣言.役割 == 関数の役割::M射影関数)
        .filter(|宣言| {
            let 同じ宣言から導いた関係 = |種類| {
                関係一覧
                    .iter()
                    .filter(move |関係| 関係.種類 == 種類 && 関係.出どころ.構文 == 抽出元の構文::関数の役割の型引数 && 関係.出どころ.パス == 宣言.出どころ.パス && 関係.出どころ.行番号 == 宣言.出どころ.行番号)
            };
            同じ宣言から導いた関係(設計関係の種類::消費する).any(|消費| 同じ宣言から導いた関係(設計関係の種類::生成する).any(|生成| 生成.目的語 == 消費.目的語))
        })
        .map(|宣言| {
            違反::行単位(
                宣言.出どころ.パス.clone(),
                宣言.出どころ.行番号,
                "射影関数の入力の状態と出力の射影が同じ型である。射影関数は状態から別の値を取り出す関数であり、状態を受けて同じ状態を返す関数は遷移か規則によらない書き換えの役割で宣言する".to_string(),
            )
        })
        .collect()
}
