//! Rustの原文を、コード・コメント・文字列リテラルの断片へ分ける字句の走査。
//! 受け取るのは原文、返すのは区分と位置の付いた断片の並びである。
//!
//! 「その語が本当に文字列リテラルの中に在るか」を2つの検査が同じ規則で判定するため、走査をここ1箇所に置く。
//! 引用符の数え上げでは判定が成立しない。コメントの中の引用符が区間を開き、逃がし記号の`\"`が区間を閉じ、
//! 生文字列の`r#"..."#`は逃がし記号を持たない。どれも「コメントでの言及」を出現と数え違える原因になる。
//!
//! 中身は区切りの記号を除いた内側であり、通常文字列は逃がし記号を実行時の文字へ復号したものである。
//! 生文字列と通常文字列が同じ中身を持つようにするためであり、これがないと同じファイル名が書き方の違いで
//! 別の綴りとして数えられる(`"a.b"`は点を持たない綴りに見える)。
//! 行数と位置は原文の区間から数える。復号した中身から数えると、`\n`の逃がし1つで以降の行番号がずれる。
//! 位置は行末を揃えた後の添字である。走査の入口で復帰改行を改行へ揃えるためであり、行の数は変わらない。

mod code_lines;
mod fragment;
#[cfg(test)]
mod position_tests;
#[cfg(test)]
mod tests;
mod token_read;

pub use code_lines::コードだけの行一覧;
pub use fragment::{字句の区分, 字句の断片};

pub fn 字句へ分ける(内容: &str) -> Vec<字句の断片> {
    let 文字一覧: Vec<char> = 行末を揃える(内容).chars().collect();
    let mut 断片一覧 = Vec::new();
    let mut コードの始まり: Option<(usize, usize)> = None;
    let mut 行番号 = 1usize;
    let mut 位置 = 0usize;
    while let Some(&文字) = 文字一覧.get(位置) {
        let Some(読み) = token_read::区切りを読む(&文字一覧, 位置) else {
            コードの始まり.get_or_insert((位置, 行番号));
            if 文字 == '\n' {
                行番号 += 1;
            }
            位置 += 1;
            continue;
        };
        溜めたコードを吐き出す(&mut 断片一覧, &文字一覧, コードの始まり.take(), 位置);
        断片一覧.push(字句の断片 {
            区分: 読み.区分,
            開始行: 行番号,
            開始位置: 位置,
            終了位置: 読み.次の位置,
            中身: 読み.中身,
        });
        行番号 += 区間の改行数(&文字一覧, 位置, 読み.次の位置);
        位置 = 読み.次の位置;
    }
    溜めたコードを吐き出す(&mut 断片一覧, &文字一覧, コードの始まり, 位置);
    断片一覧
}

pub fn 文字列リテラル一覧(内容: &str) -> Vec<字句の断片> {
    字句へ分ける(内容)
        .into_iter()
        .filter(|断片| 断片.区分 == 字句の区分::文字列リテラル)
        .collect()
}

fn 溜めたコードを吐き出す(
    断片一覧: &mut Vec<字句の断片>, 文字一覧: &[char], 始まり: Option<(usize, usize)>, 終了位置: usize
) {
    let Some((開始位置, 開始行)) = 始まり else {
        return;
    };
    断片一覧.push(字句の断片 {
        区分: 字句の区分::コード,
        開始行,
        開始位置,
        終了位置,
        中身: 文字一覧[開始位置..終了位置].iter().collect(),
    });
}

/// 復帰改行を改行へ揃える。rustcが字句へ分ける前に同じ変換を行うため、行末の逃がしによる継続は
/// 復帰改行のファイルでも成り立つ。揃えずに読むと、逃がしの次の復帰を知らない逃がしとして残し、
/// 継ぎ目で切れた綴りを別の名前として数える。行の数は変わらないため、行番号の数え方は揃えても動かない。
fn 行末を揃える(内容: &str) -> String {
    内容.replace("\r\n", "\n")
}

fn 区間の改行数(文字一覧: &[char], 開始位置: usize, 終了位置: usize) -> usize {
    文字一覧[開始位置..終了位置.min(文字一覧.len())]
        .iter()
        .filter(|文字| **文字 == '\n')
        .count()
}
