//! Graphite(Rustの型で検査されるグラフの記述言語)のコードを、規約の検査がどう扱うかを1か所に持つ木。
//!
//! Graphiteのコードは2種類ある。1つは利用者が手で書く宣言(`dynamic_graph_schema!`・`static_graph_schema!`・`graph!` と、生成物を取り込む `mod`)であり、
//! もう1つはGraphiteの生成器が書き出す生成物である。生成物はGraphiteの固定の語彙を展開したものであり、手編集を禁じられているため、
//! 行数・1つの宣言へ2行以上積んだ説明の注釈・参照パスの実在の3検査と、設計解釈マーカーの実装の置き場の警告と、型ごとの分量の台帳の検査と、親の型を丸ごと受け取る自由関数の検査と、設計関係の抽出から外す(2026-09-26のオーナー裁定。型ごとの分量の台帳と自由関数の検査は同日の作業G1で足した。単独の `cargo xtask type-metrics` も同じく外す。Issue #187)。
//! 宣言の間のコメントだけの行の検査は外さない。裁定が外したのは説明の注釈の行数だけであり、コメントだけの行は生成物にも当てる。
//!
//! 生成物かどうかは置き場のパスでなく、生成物の先頭の見出しで見分ける。パスで見分けると、手書きのコードをその場所へ置くだけで検査を抜けられるためである。
//! 見出しは誰でも書けるため、見出しが名乗る生成元のファイルが、そのファイルを生成先として宣言していることも確かめる。
//! 結び付かない見出しを持つファイルは生成物と認めず、3検査を当てたうえで、偽の見出しとして違反にする。
//!
//! 検査しないこと: 生成物の本文が生成器の出力と一致しているか。これを確かめるのは `cargo graphite generate --check` であり、この木は生成器を持たない。
//! 利用者が手で書くGraphiteのコードは、マクロの本体の行だけを行数の数えから除く(`xtask/src/conform/graphiteのコード/マクロの本体.rs`)。ファイルの残りの行には1ファイル100行の原則を当てる。
//! 参照: CLAUDE.md「ファイル・関数の分割」。

