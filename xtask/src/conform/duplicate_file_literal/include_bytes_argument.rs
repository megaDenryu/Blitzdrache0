//! 文字列リテラルが`include_bytes!`の引数の中に在るかの判定。受け取るのは字句の断片の並び、
//! 返すのは引数の括弧が覆う原文の区間の一覧である。
//!
//! 同じ行に呼び出しが在るかだけで見ると、その行の別のリテラルまで引数として数える。取り込みかどうかは
//! ビルド時の成果物を許す規則の根拠そのものであり、根拠の成り立たないリテラルを取り込みと数えると
//! 規則が実際より広く許すことになる。括弧の対応で区間を作り、その内側に在るかで見る。
//!
//! 括弧を数えるのはコードの断片だけである。文字列やコメントの中の括弧を数えると区間が閉じない。

use crate::conform::source_lexing::{字句の区分, 字句の断片};

const 取り込みの呼び出し: &str = "include_bytes!";

pub(super) fn 取り込みの引数の区間一覧(断片一覧: &[字句の断片]) -> Vec<(usize, usize)> {
    断片一覧
        .iter()
        .filter(|断片| 断片.区分 == 字句の区分::コード)
        .flat_map(呼び出しの位置一覧)
        .filter_map(|呼び出しの位置| 引数の区間を求める(断片一覧, 呼び出しの位置))
        .collect()
}

pub(super) fn 区間の中か(区間一覧: &[(usize, usize)], 位置: usize) -> bool {
    区間一覧.iter().any(|(始まり, 終わり)| (*始まり..*終わり).contains(&位置))
}

/// 断片の中の呼び出しの出現を、原文の文字の添字へ写す。
fn 呼び出しの位置一覧(断片: &字句の断片) -> Vec<usize> {
    断片
        .中身
        .match_indices(取り込みの呼び出し)
        .map(|(バイト位置, _)| 断片.開始位置 + 断片.中身[..バイト位置].chars().count())
        .collect()
}

/// 呼び出しに続く最初の括弧から、その対応が閉じるまでの区間。閉じない場合は区間を作らない。
fn 引数の区間を求める(断片一覧: &[字句の断片], 呼び出しの位置: usize) -> Option<(usize, usize)> {
    let mut 深さ = 0usize;
    let mut 開いた位置 = None;
    for (位置, 文字) in コードの文字を並べる(断片一覧, 呼び出しの位置) {
        match 文字 {
            '(' => {
                深さ += 1;
                開いた位置.get_or_insert(位置);
            }
            ')' => {
                深さ = 深さ.saturating_sub(1);
                if 深さ == 0 {
                    return 開いた位置.map(|開いた位置| (開いた位置, 位置));
                }
            }
            _ => {}
        }
    }
    None
}

/// 指定の位置から後ろのコードの文字を、原文の文字の添字を添えて並べる。
fn コードの文字を並べる(断片一覧: &[字句の断片], 開始位置: usize) -> impl Iterator<Item = (usize, char)> + '_ {
    断片一覧
        .iter()
        .filter(move |断片| 断片.区分 == 字句の区分::コード && 断片.終了位置 > 開始位置)
        .flat_map(move |断片| {
            断片
                .中身
                .chars()
                .enumerate()
                .map(|(ずれ, 文字)| (断片.開始位置 + ずれ, 文字))
                .filter(move |(位置, _)| *位置 >= 開始位置)
        })
}
