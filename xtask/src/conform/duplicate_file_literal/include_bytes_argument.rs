//! 文字列リテラルが組み込みの`include_bytes!`の引数の中に在るかの判定。受け取るのは字句の断片の並び、
//! 返すのは引数の括弧が覆う原文の区間の一覧である。
//!
//! 同じ行に呼び出しが在るかだけで見ると、その行の別のリテラルまで引数として数える。取り込みかどうかは
//! ビルド時の成果物を許す規則の根拠そのものであり、根拠の成り立たないリテラルを取り込みと数えると
//! 規則が実際より広く許すことになる。括弧の対応で区間を作り、その内側に在るかで見る。
//!
//! 受けるのは、名前の境界で始まり、パスの修飾を持たない呼び出しだけである。修飾された呼び出しは
//! 別のマクロを指しうるため、「食い違いはコンパイルが捉える」という根拠が成り立たない。
//! 組み込みと同じ名前のマクロを定義したり取り込んだりすること自体は`builtin_include_bytes`が禁じる。
//!
//! 判定はコードの断片だけを連ねた並びの上で行う。文字列やコメントの中の括弧や語が数に入らず、
//! 呼び出しの直前を遡るときにコメントを跨げる。

mod code_sequence;

use code_sequence::コードの並び;

use crate::conform::source_lexing::字句の断片;

pub(super) fn 取り込みの引数の区間一覧(断片一覧: &[字句の断片]) -> Vec<(usize, usize)> {
    let 並び = コードの並び::組む(断片一覧);
    並び
        .組み込みの呼び出しの添字一覧()
        .into_iter()
        .filter_map(|添字| 並び.引数の区間を求める(添字))
        .collect()
}

pub(super) fn 区間の中か(区間一覧: &[(usize, usize)], 位置: usize) -> bool {
    区間一覧.iter().any(|(始まり, 終わり)| (*始まり..*終わり).contains(&位置))
}
