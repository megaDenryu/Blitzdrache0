//! コードの断片だけを連ねた文字の並びと、その上での呼び出しの見つけ方。
//! 受け取るのは字句の断片の並び、返すのは原文の位置で表した引数の区間である。
//!
//! 文字列とコメントを落とした並びの上で見るのは、判定の材料をコードだけに限るためである。
//! これがないと、コメントの中の語を呼び出しと数え、文字列の中の括弧で区間が閉じなくなる。

use crate::conform::source_lexing::{字句の区分, 字句の断片};

const 取り込みの呼び出し: &str = "include_bytes!";

pub(super) struct コードの並び {
    文字一覧: Vec<char>,
    原文の位置一覧: Vec<usize>, // 同じ添字の文字が原文のどこに在るか
}

impl コードの並び {
    pub(super) fn 組む(断片一覧: &[字句の断片]) -> Self {
        let mut 文字一覧 = Vec::new();
        let mut 原文の位置一覧 = Vec::new();
        for 断片 in 断片一覧.iter().filter(|断片| 断片.区分 == 字句の区分::コード) {
            for (ずれ, 文字) in 断片.中身.chars().enumerate() {
                文字一覧.push(文字);
                原文の位置一覧.push(断片.開始位置 + ずれ);
            }
        }
        Self {
            文字一覧, 原文の位置一覧
        }
    }

    /// 組み込みの取り込みを指す呼び出しの添字。名前の境界で始まり、パスの修飾を持たないものだけを返す。
    pub(super) fn 組み込みの呼び出しの添字一覧(&self) -> Vec<usize> {
        let 名前: Vec<char> = 取り込みの呼び出し.chars().collect();
        self.文字一覧
            .windows(名前.len())
            .enumerate()
            .filter(|(_, 窓)| *窓 == 名前.as_slice())
            .map(|(添字, _)| 添字)
            .filter(|添字| self.名前の始まりか(*添字) && !self.パスの修飾を持つか(*添字))
            .collect()
    }

    /// 呼び出しに続く最初の括弧から、その対応が閉じるまでの原文の区間。閉じない場合は区間を作らない。
    pub(super) fn 引数の区間を求める(&self, 呼び出しの添字: usize) -> Option<(usize, usize)> {
        let mut 深さ = 0usize;
        let mut 開いた添字 = None;
        for (添字, 文字) in self.文字一覧.iter().enumerate().skip(呼び出しの添字) {
            match 文字 {
                '(' => {
                    深さ += 1;
                    開いた添字.get_or_insert(添字);
                }
                ')' => {
                    深さ = 深さ.saturating_sub(1);
                    if 深さ == 0 {
                        return 開いた添字.map(|開いた添字| (self.原文の位置一覧[開いた添字], self.原文の位置一覧[添字]));
                    }
                }
                _ => {}
            }
        }
        None
    }

    /// その添字から名前が始まるか。直前の文字が名前の続きなら、より長い名前の一部である。
    fn 名前の始まりか(&self, 添字: usize) -> bool {
        添字 == 0 || !名前の続きか(self.文字一覧[添字 - 1])
    }

    /// 直前を空白だけ遡って`::`が在るか。パスで修飾された呼び出しは組み込み以外を指しうる。
    fn パスの修飾を持つか(&self, 添字: usize) -> bool {
        let 空白の手前 = self.文字一覧[..添字].iter().rposition(|文字| !文字.is_whitespace());
        空白の手前.is_some_and(|位置| self.文字一覧[位置] == ':' && 位置 > 0 && self.文字一覧[位置 - 1] == ':')
    }
}

/// 名前の続きとみなす文字。Rustの規則(XID_Continue)そのものの判定には外部のクレートが要り、
/// xtaskの依存を持たない方針と衝突するため、その上位集合であるASCIIの英数字と下線とASCII外の全部を使う。
/// 上位集合にすると名前の境界と認める場合が狭まり、取り込みと認める呼び出しも狭まる。
/// すり抜け(許しすぎ)は起こらず、許さなすぎた場合だけが違反として人の目に出る。
fn 名前の続きか(文字: char) -> bool {
    文字.is_ascii_alphanumeric() || 文字 == '_' || !文字.is_ascii()
}
