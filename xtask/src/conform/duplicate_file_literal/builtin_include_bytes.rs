//! 取り込みの名前を組み込み以外へ結ぶ宣言の禁止。受け取るのは走査するファイルの一覧、
//! 返すのはその宣言を書いたファイルの違反一覧である。
//!
//! ビルド時の成果物の綴りを許す規則は「取り込みが実在しないファイルを指せばコンパイルが失敗する」ことを
//! 根拠にしており、それは組み込みの取り込みにしか成り立たない。同じ名前のマクロを定義したり別の場所から
//! 取り込んだりすると、規則が根拠を失ったまま許し続ける。名前を奪う宣言そのものをここが禁じる。
//!
//! 検出の綴りを1つの並びで書くと、この検査が自分自身を違反として報告するため、分けて連結する。

use std::path::{Path, PathBuf};

use crate::conform::source_lexing::コードだけの行一覧;
use crate::conform::violation::違反;

const 定義の綴り: [&str; 2] = ["macro_rules!", concat!("include_", "bytes")];
const 取り込みの綴り: [&str; 2] = ["use ", concat!("include_", "bytes")];
const 禁じる理由: &str = "組み込みの取り込みの名前を奪う宣言である(ビルド時の成果物の綴りを許す規則の根拠を壊すため禁じる)";

pub(super) fn 全ファイルを検査する(ファイル一覧: &[PathBuf]) -> Result<Vec<違反>, String> {
    let mut 違反一覧 = Vec::new();
    for パス in ファイル一覧 {
        let 内容 = std::fs::read_to_string(パス).map_err(|誤り| format!("{}の読み取りに失敗した: {誤り}", パス.display()))?;
        違反一覧.extend(ファイル1つを検査する(パス, &内容));
    }
    Ok(違反一覧)
}

/// コードだけの行を見るのは、コメントや文字列での言及を宣言と読み違えないためである。
pub(super) fn ファイル1つを検査する(パス: &Path, 内容: &str) -> Vec<違反> {
    コードだけの行一覧(内容)
        .iter()
        .enumerate()
        .filter(|(_, 行)| 名前を奪う宣言か(行))
        .map(|(添字, _)| 違反::行単位(パス.to_path_buf(), 添字 + 1, 禁じる理由.to_string()))
        .collect()
}

fn 名前を奪う宣言か(行: &str) -> bool {
    [定義の綴り, 取り込みの綴り]
        .iter()
        .any(|綴り一覧| 綴り一覧.iter().all(|綴り| 行.contains(綴り)))
}
