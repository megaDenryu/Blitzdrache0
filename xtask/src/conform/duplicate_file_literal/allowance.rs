//! 2箇所以上に書いてよい、ファイル名らしい綴りの台帳と、台帳を持つまでもない1つの規則。
//! ここへ載せてよいのは、正本を1箇所へ寄せられないものだけである。寄せられるものを載せるのは、
//! この検査を無効にすることと同じである。
//! 参照: `_doc/計画/構造是正計画.md`「工事の一覧(依存順)」。

mod build_output;

use std::path::{Path, PathBuf};

pub(super) use build_output::ビルド時に焼いて取り込むシェーダー中間表現の名前か;

use crate::conform::violation::違反;

/// 寄せられない綴りと、その理由。理由を綴りと並べて持つのは、台帳を減らすときに
/// 「何が変われば消せるのか」を読み手が判断できるようにするためである。
pub(super) struct 寄せられない綴り {
    pub(super) 綴り: &'static str,
    pub(super) 寄せられない理由: &'static str,
}

const ビルドスクリプトとの契約: &str = "blitz_appのビルドスクリプトが読む入力の名前であり、本体も同じ入力を実行中に読む。build_supportはビルドスクリプトのモジュールで本体から参照できないため、両側が同じ綴りを持つほかない";

/// 注意: この一覧への追加は禁止する。減らす方向にのみ動かす。
/// 削除できるのは、その綴りの正本を1箇所へ寄せたときだけである。
const 許した綴り一覧: [寄せられない綴り; 3] = [
    寄せられない綴り {
        綴り: "scene.slang",
        寄せられない理由: "blitz_appのビルドスクリプトとxtaskが別のクレートに在り、xtaskからビルドスクリプトへ依存を張れない",
    },
    寄せられない綴り {
        綴り: "scene_distant_environment.slang",
        寄せられない理由: ビルドスクリプトとの契約,
    },
    寄せられない綴り {
        綴り: "slangc.exe",
        寄せられない理由: ビルドスクリプトとの契約,
    },
];

pub(super) fn 既知の寄せられない綴りか(綴り: &str, 出現するパス一覧: &[&Path]) -> bool {
    許した綴り一覧.iter().any(|許容| 許容.綴り == 綴り)
        || ビルド時に焼いて取り込むシェーダー中間表現の名前か(綴り, 出現するパス一覧)
}

/// 台帳に載っているのに重複していない綴りを違反として報告し、台帳からの削除を強制する。
/// これがないと是正済みの綴りが残り続け、次に同じ綴りを2箇所へ書いたときに見逃す穴になる。
pub(super) fn 台帳の陳腐化を検査する(重複した綴り一覧: &[String]) -> Vec<違反> {
    許した綴り一覧
        .iter()
        .filter(|許容| !重複した綴り一覧.iter().any(|重複| 重複 == 許容.綴り))
        .map(|許容| {
            違反::ファイル単位(
                PathBuf::from("xtask/src/conform/duplicate_file_literal/allowance.rs"),
                format!(
                    "台帳が許した綴り「{}」はもう2箇所に無い(台帳から削除する。載せた理由は「{}」)",
                    許容.綴り, 許容.寄せられない理由
                ),
            )
        })
        .collect()
}
