//! ビルド時に焼いて、そのままビルド時に取り込む成果物の対かの判定。受け取るのは綴りと出現の並び、
//! 返すのはこの検査が重ねて見る必要のない対かどうかである。
//!
//! 台帳へ1件ずつ載せずに規則で許すのは、この対の食い違いを機械が既に捉えているからである。
//! ビルドスクリプトが焼いた名前と`include_bytes!`が取り込む名前がずれると、取り込みが実在しない
//! ファイルを指してコンパイルが失敗する。50件を超える名前を台帳へ書き写しても、守る対象が増えない。
//!
//! 根拠が成り立つのは、焼く側が1つで、ほかの出現が全部その成果物の取り込みであるときだけである。
//! 取り込み以外の出現(実行中に同じ名前の別ファイルを作る経路など)はコンパイルでは捉えられないため、
//! 1つでも混ざれば規則は許さない。取り込みが3つ以上あっても許すのは、どの取り込みも同じ根拠で守られるためである。

use std::path::Path;

use crate::conform::duplicate_file_literal::出現箇所;

const 取り込む成果物の拡張子: &str = ".spv";
const ビルドスクリプトの置き場: &str = "build_support";

pub(in crate::conform::duplicate_file_literal) fn 焼いてそのまま取り込む対か(綴り: &str, 出現一覧: &[&出現箇所]) -> bool {
    if !綴り.ends_with(取り込む成果物の拡張子) {
        return false;
    }
    let (焼く側, ほか): (Vec<&&出現箇所>, Vec<&&出現箇所>) = 出現一覧.iter().partition(|出現| ビルドスクリプトの中か(&出現.パス));
    焼く側.len() == 1 && !ほか.is_empty() && ほか.iter().all(|出現| 出現.取り込みの引数か)
}

fn ビルドスクリプトの中か(パス: &Path) -> bool {
    パス.components().any(|部品| 部品.as_os_str() == ビルドスクリプトの置き場)
}
