//! ビルド時に焼いてビルド時に取り込むSPIR-Vの名前かの判定。受け取るのは綴りと出現するパスの並び、
//! 返すのはこの検査が重ねて見る必要のない綴りかどうかである。
//!
//! 台帳へ1件ずつ載せずに規則で許すのは、この綴りの食い違いを機械が既に捉えているからである。
//! ビルドスクリプトが焼いた名前と`include_bytes!`が取り込む名前がずれると、取り込みが実在しない
//! ファイルを指してコンパイルが失敗する。50件を超える名前を台帳へ書き写しても、守る対象が増えない。
//!
//! 規則を狭く保つため、条件は3つそろったときだけである。綴りがSPIR-Vの拡張子で終わること、
//! 出現の1つがビルドスクリプトの中に在ること、出現の全部がそのクレートの中に収まっていることである。

use std::path::Path;

const 取り込むシェーダー中間表現の拡張子: &str = ".spv";
const ビルドスクリプトの置き場: &str = "build_support";
const 焼いて取り込むクレート: &str = "blitz_app";

pub(in crate::conform::duplicate_file_literal) fn ビルド時に焼いて取り込むシェーダー中間表現の名前か(
    綴り: &str,
    出現するパス一覧: &[&Path],
) -> bool {
    綴り.ends_with(取り込むシェーダー中間表現の拡張子)
        && 出現するパス一覧.iter().any(|パス| 部品に持つか(パス, ビルドスクリプトの置き場))
        && 出現するパス一覧.iter().all(|パス| 部品に持つか(パス, 焼いて取り込むクレート))
}

fn 部品に持つか(パス: &Path, 名前: &str) -> bool {
    パス.components().any(|部品| 部品.as_os_str() == 名前)
}
