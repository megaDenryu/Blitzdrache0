//! 原文の各行がコードを含むか・コメントを含むかを、行番号順に返す工程。受け取るのは原文、返すのは行ごとの内訳である。
//!
//! 行数検査と宣言の並びの検査が同じ判定を使うため、走査をここ1箇所に置く。行の内訳を原文の区間から数えるのは、
//! 文字列リテラルの中身が逃がし記号を復号したものであり、`\n`の逃がし1つで以降の行の対応がずれるためである。

use super::{字句の区分, 字句の断片, 字句へ分ける};

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct 行の内訳 {
    pub コードを含む: bool,   // 空白以外の文字が、コメントの外に在る
    pub コメントを含む: bool, // 行コメントかブロックコメントの区間が、その行に掛かる
}

pub fn 行ごとの内訳(内容: &str) -> Vec<行の内訳> {
    let 原文: Vec<char> = 内容.replace("\r\n", "\n").chars().collect();
    let mut 一覧 = vec![行の内訳::default(); 内容.lines().count()];
    for 断片 in 字句へ分ける(内容) {
        let コメントか = matches!(断片.区分, 字句の区分::行コメント | 字句の区分::ブロックコメント);
        印を付ける(&原文, &断片, コメントか, &mut 一覧);
    }
    一覧
}

/// 断片が占める区間を原文の上で辿り、空白以外の文字が在る行へ印を付ける。
fn 印を付ける(原文: &[char], 断片: &字句の断片, コメントか: bool, 一覧: &mut [行の内訳]) {
    let mut 行番号 = 断片.開始行;
    for 添字 in 断片.開始位置..断片.終了位置 {
        match 原文.get(添字) {
            Some('\n') => 行番号 += 1,
            Some(文字) if !文字.is_whitespace() => {
                if let Some(内訳) = 一覧.get_mut(行番号 - 1) {
                    if コメントか {
                        内訳.コメントを含む = true;
                    } else {
                        内訳.コードを含む = true;
                    }
                }
            }
            _ => {}
        }
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn 行末のコメントが付いた行はコードとコメントの両方を含む() {
        let 一覧 = 行ごとの内訳("let a = 1; // 説明\n");
        assert_eq!(
            一覧[0],
            行の内訳 {
                コードを含む: true,
                コメントを含む: true
            }
        );
    }

    #[test]
    fn コメントだけの行はコードを含まない() {
        let 一覧 = 行ごとの内訳("// 説明\nlet a = 1;\n");
        assert_eq!(
            一覧[0],
            行の内訳 {
                コードを含む: false,
                コメントを含む: true
            }
        );
        assert_eq!(
            一覧[1],
            行の内訳 {
                コードを含む: true,
                コメントを含む: false
            }
        );
    }

    #[test]
    fn 空行はどちらも含まない() {
        assert_eq!(行ごとの内訳("\nlet a = 1;\n")[0], 行の内訳::default());
    }

    #[test]
    fn 複数行のブロックコメントは掛かる全ての行へ印が付く() {
        let 一覧 = 行ごとの内訳("/* 一行目\n二行目 */\nlet a = 1;\n");
        assert!(一覧[0].コメントを含む && !一覧[0].コードを含む);
        assert!(一覧[1].コメントを含む && !一覧[1].コードを含む);
        assert!(一覧[2].コードを含む);
    }

    #[test]
    fn 文字列リテラルの中の改行の逃がしで行がずれない() {
        let 一覧 = 行ごとの内訳(concat!(r#"let a = "一行目\n二行目";"#, "\n// 説明\n"));
        assert!(一覧[0].コードを含む && !一覧[0].コメントを含む);
        assert!(一覧[1].コメントを含む && !一覧[1].コードを含む);
    }
}
