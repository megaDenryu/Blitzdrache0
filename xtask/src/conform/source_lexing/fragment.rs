//! 字句の走査が返す断片の型。区分と、原文の中での位置と、区切りの記号を除いた中身を持つ。
//!
//! 位置を原文の文字の添字で持つのは、`include_bytes!`の括弧の中に在るかのように、
//! 「どの呼び出しの内側の綴りか」を後から判定する検査があるためである。行番号だけでは同じ行の別の
//! リテラルと区別できない。
//!
//! `中身`の通常文字列は逃がし記号を復号したものであり、`開始位置`と`終了位置`が挟む原文の長さとは一致しない。

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 字句の区分 {
    コード,
    行コメント,
    ブロックコメント,
    文字列リテラル,
    文字リテラル,
}

#[derive(Debug, PartialEq, Eq)]
pub struct 字句の断片 {
    pub 区分: 字句の区分,
    pub 開始行: usize,
    pub 開始位置: usize, // 原文の文字の添字。区切りの記号を含む区間の始まり
    pub 終了位置: usize, // 区間の終わりの次。区切りの記号を含む
    pub 中身: String,    // 区切りの記号を除いた内側
}

impl 字句の断片 {
    /// `///`で始まる説明の注釈かを判定する。行コメントの`中身`は`//`を除いた内側であり、
    /// `///`なら1つの斜線で始まる。rustcが説明として扱わない`////`の並びと、内側向けの`//!`は外す。
    /// ブロックの`/** */`は判定に入れない。宣言の前へ複数行で書けてしまい、1宣言1行の裁定を測れないためである。
    pub fn 説明の注釈か(&self) -> bool {
        self.区分 == 字句の区分::行コメント && self.中身.starts_with('/') && !self.中身.starts_with("//")
    }
}
