//! 文字列リテラルと文字リテラルの区間を読む工程。受け取るのは文字の並びと開始位置、
//! 返すのは区間の中身と次の位置である。中身は引用符と接頭辞を除いた内側である。
//!
//! 生文字列を先に試すのは、`r#"`の`r`を識別子の一部と読むと中の`"`が区間を開いてしまうためである。

use super::escape::逃がしを復号する;
use super::{字句の区分, 文字を集める, 読み取り};

/// `r"..."`と`r#"..."#`と`br##"..."##`。井桁の数だけ終端の井桁を求める。
pub(super) fn 生文字列を読む(文字一覧: &[char], 位置: usize) -> Option<読み取り> {
    let 接頭辞の長さ = if 文字一覧.get(位置) == Some(&'r') {
        1
    } else if 文字一覧.get(位置) == Some(&'b') && 文字一覧.get(位置 + 1) == Some(&'r') {
        2
    } else {
        return None;
    };
    let 井桁の数 = (位置 + 接頭辞の長さ..文字一覧.len()).take_while(|添字| 文字一覧[*添字] == '#').count();
    let 引用符の位置 = 位置 + 接頭辞の長さ + 井桁の数;
    if 文字一覧.get(引用符の位置) != Some(&'"') {
        return None;
    }
    let 内側の開始 = 引用符の位置 + 1;
    let 終端 = 生文字列の終端を探す(文字一覧, 内側の開始, 井桁の数);
    Some(読み取り {
        区分: 字句の区分::文字列リテラル,
        中身: 文字を集める(文字一覧, 内側の開始, 終端),
        次の位置: (終端 + 1 + 井桁の数).min(文字一覧.len()),
    })
}

fn 生文字列の終端を探す(文字一覧: &[char], 内側の開始: usize, 井桁の数: usize) -> usize {
    let mut 添字 = 内側の開始;
    while 添字 < 文字一覧.len() {
        let 閉じか = 文字一覧[添字] == '"' && (1..=井桁の数).all(|ずれ| 文字一覧.get(添字 + ずれ) == Some(&'#'));
        if 閉じか {
            return 添字;
        }
        添字 += 1;
    }
    文字一覧.len()
}

/// `"..."`と`b"..."`。逃がし記号の次の1文字は終端の判定から外す。
pub(super) fn 通常文字列を読む(文字一覧: &[char], 位置: usize) -> Option<読み取り> {
    let 接頭辞の長さ = if 文字一覧.get(位置) == Some(&'"') {
        0
    } else if 文字一覧.get(位置) == Some(&'b') && 文字一覧.get(位置 + 1) == Some(&'"') {
        1
    } else {
        return None;
    };
    let 内側の開始 = 位置 + 接頭辞の長さ + 1;
    let mut 添字 = 内側の開始;
    while let Some(&文字) = 文字一覧.get(添字) {
        match 文字 {
            '\\' => 添字 += 2,
            '"' => break,
            _ => 添字 += 1,
        }
    }
    let 終端 = 添字.min(文字一覧.len());
    Some(読み取り {
        区分: 字句の区分::文字列リテラル,
        中身: 逃がしを復号する(&文字を集める(文字一覧, 内側の開始, 終端)),
        次の位置: (終端 + 1).min(文字一覧.len()),
    })
}

/// `'x'`と`'\''`。閉じの引用符が無ければライフタイムであり、読まずにNoneを返す。
pub(super) fn 文字リテラルを読む(文字一覧: &[char], 位置: usize) -> Option<読み取り> {
    if 文字一覧.get(位置) != Some(&'\'') {
        return None;
    }
    let 内側の長さ = if 文字一覧.get(位置 + 1) == Some(&'\\') { 2 } else { 1 };
    let 閉じの位置 = 位置 + 1 + 内側の長さ;
    if 文字一覧.get(閉じの位置) != Some(&'\'') {
        return None;
    }
    Some(読み取り {
        区分: 字句の区分::文字リテラル,
        中身: 文字を集める(文字一覧, 位置 + 1, 閉じの位置),
        次の位置: 閉じの位置 + 1,
    })
}
