//! コメントの区間を読む工程。受け取るのは文字の並びと開始位置、返すのは区間の中身と次の位置である。
//! 中身は`//`や`/* */`の記号を除いた内側である。ブロックコメントの入れ子を数えるのは、Rustが入れ子を許すためである。

use super::{二文字が続くか, 字句の区分, 文字を集める, 読み取り};

pub(super) fn 行コメントを読む(文字一覧: &[char], 位置: usize) -> Option<読み取り> {
    if !二文字が続くか(文字一覧, 位置, '/', '/') {
        return None;
    }
    let 終端 = (位置..文字一覧.len()).find(|添字| 文字一覧[*添字] == '\n').unwrap_or(文字一覧.len());
    Some(読み取り {
        区分: 字句の区分::行コメント,
        中身: 文字を集める(文字一覧, 位置 + 2, 終端),
        次の位置: 終端,
    })
}

pub(super) fn ブロックコメントを読む(文字一覧: &[char], 位置: usize) -> Option<読み取り> {
    if !二文字が続くか(文字一覧, 位置, '/', '*') {
        return None;
    }
    let mut 深さ = 1usize;
    let mut 添字 = 位置 + 2;
    while 添字 < 文字一覧.len() && 深さ > 0 {
        if 二文字が続くか(文字一覧, 添字, '/', '*') {
            深さ += 1;
            添字 += 2;
            continue;
        }
        if 二文字が続くか(文字一覧, 添字, '*', '/') {
            深さ -= 1;
            添字 += 2;
            continue;
        }
        添字 += 1;
    }
    let 内側の終端 = if 深さ == 0 { 添字 - 2 } else { 添字 };
    Some(読み取り {
        区分: 字句の区分::ブロックコメント,
        中身: 文字を集める(文字一覧, 位置 + 2, 内側の終端),
        次の位置: 添字,
    })
}
