//! 照明問い合わせのスロットへ書き込む地点が1つだけであることの検査。受け取るのは無し(対象の表がここにある)、
//! 返すのは書き込みの呼び出し元が増えた場合の違反一覧である。
//!
//! スロットのバッファへ書けるのは、そのスロットの描画完了フェンスを通過した後だけである。書き込みの呼び出し元が
//! 増えると、フェンスを待たない地点からGPUが読んでいる最中のバッファを書き換える経路が生まれる。呼び出し元が
//! 1つであれば、その1つがフェンス待ちの後にあることの確認で規律が閉じる
//! (参照: `_doc/設計/GPU資源束縛の分離と索引化.md`「段階導入」の段5の検収ゲート(i))。

use std::path::PathBuf;

use super::error::規約検査の破れ;
use super::violation::違反;
use crate::file_scan;

const 走査対象ディレクトリ一覧: [&str; 1] = ["crates"];
const 走査対象拡張子一覧: [&str; 1] = ["rs"];
/// 書き込みのメソッド名。定義と呼び出しの両方がこの綴りを持つ。
const 書き込みの名前: &str = "スロットへ書き込む";
/// 定義を持つファイル。ここでの出現は呼び出しでなく定義として数えない。
const 定義ファイル: &str = "lighting_query/mod.rs";
/// 唯一の呼び出し元。フェンス待ちの後に呼ばれることをこのファイルの冒頭が述べる。
const 唯一の呼び出し元: &str = "renderer/uniform_write.rs";

pub fn 検査する() -> Result<Vec<違反>, 規約検査の破れ> {
    let ファイル一覧 = file_scan::対象ファイル一覧を集める(&走査対象ディレクトリ一覧, &走査対象拡張子一覧)?;
    let mut 違反一覧 = Vec::new();
    let mut 呼び出し元を見たか = false;
    for パス in &ファイル一覧 {
        let 表示 = パス.display().to_string().replace(std::path::MAIN_SEPARATOR, "/");
        let 内容 = std::fs::read_to_string(パス).map_err(|誤り| 規約検査の破れ::ファイルを読めなかった(パス, 誤り))?;
        if !内容.contains(書き込みの名前) || 表示.ends_with(定義ファイル) {
            continue;
        }
        if 表示.ends_with(唯一の呼び出し元) {
            呼び出し元を見たか = true;
            continue;
        }
        違反一覧.push(違反::ファイル単位(
            PathBuf::from(パス),
            format!("照明問い合わせのスロットへの書き込みが{唯一の呼び出し元}以外から呼ばれている"),
        ));
    }
    if !呼び出し元を見たか {
        違反一覧.push(違反::ファイル単位(
            PathBuf::from(唯一の呼び出し元),
            "照明問い合わせのスロットへの書き込みの呼び出しが消えている".to_string(),
        ));
    }
    Ok(違反一覧)
}
