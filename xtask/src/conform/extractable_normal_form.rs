//! 設計関係の抽出器が受理する正規形のRustの構文を強制する検査。受け取るのは無し、返すのは違反一覧か、抽出を実行できなかった理由である。
//!
//! この検査が在るのは、Rustとして合法でありながら抽出器の保証範囲の外である文字列を、リポジトリから無くすためである。
//! 範囲の外の文字列は抽出の側で `関係を落とした抽出の欠落` に数えられ、辺の不在を根拠にする命題を未決定へ倒す。
//! 文字列を書けなくすれば、欠落を増やさずにその領域が空になる。
//!
//! 判定を自分で持たず、抽出の結末が数えた `抽出できなかった行` の中から `保証範囲の外の構文` を名乗る行だけを拾う。
//! 判定を2つ持つと、抽出が受理する形と検査が強制する形が食い違い、検査を通った文字列から抽出が欠落を出す事故が起きる。
//! 強制の範囲は抽出の規則と同じく、設計オントロジーの適用範囲のクレート(`xtask/src/design_model/extract/ontology_scope.rs`)の本番のソースである。

use super::error::規約検査の破れ;
use super::violation::違反;
use crate::design_model::{保証範囲の外の構文, 抽出できなかった行, 設計関係グラフを抽出する};

pub fn 全ソースを検査する() -> Result<Vec<違反>, 規約検査の破れ> {
    let 結末 = 設計関係グラフを抽出する()?;
    Ok(結末.抽出できなかった行一覧.iter().filter_map(正規形の外の違反へ写す).collect())
}

// 抽出できなかった行1件を、保証範囲の外を名乗るときだけ違反へ写す。残る理由は正規形の問題ではないため写さない。
fn 正規形の外の違反へ写す(行: &抽出できなかった行) -> Option<違反> {
    let 構文: &保証範囲の外の構文 = 行.理由.保証範囲の外の構文を採る()?;
    Some(違反::行単位(行.パス.clone(), 行.行番号, format!("設計関係の抽出器が受理する正規形の外である: {}", 構文.説明())))
}
