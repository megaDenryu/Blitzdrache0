//! 助詞形「Xの節」の参照から節名を読み取る。日本語の文では語の切れ目を機械判定できないため、
//! 左端は句読点・括弧・空白までとし、指示語を拾わないよう文字数の下限を置く。下限を数える前に、
//! 両端のマークダウンの強調と引用の記号を外す(記号が文字数を嵩上げして指示語をすり抜けさせるため)。

const 節名の最短文字数: usize = 3;
const 区切り文字一覧: [char; 14] = ['、', '。', '「', '」', '『', '』', '(', ')', '（', '）', ' ', '\t', ',', '.'];
const 語末に続く文字一覧: [char; 15] = ['を', 'に', 'へ', 'で', 'が', 'は', 'も', 'と', 'の', 'や', '。', '、', '）', ')', ' '];
const 飾りの記号一覧: [char; 3] = ['*', '_', '`'];

pub fn 節名を抽出する(行: &str) -> Vec<String> {
    let mut 結果 = Vec::new();
    let mut 走査位置 = 0;
    while let Some(相対位置) = 行[走査位置..].find("の節") {
        let 位置 = 走査位置 + 相対位置;
        走査位置 = 位置 + "の節".len();
        let 遡った = 区切りまで遡る(&行[..位置]);
        let 候補 = 飾りの記号を外す(&遡った);
        if 節が語末か(&行[走査位置..]) && 候補.chars().count() >= 節名の最短文字数 {
            結果.push(候補.to_owned());
        }
    }
    結果
}

/// 候補の両端からマークダウンの強調と引用の記号を外す。節名にこれらの記号は入らないため、
/// 外さずに文字数を数えると、`**この節` のように記号のぶんだけ嵩んだ指示語が下限をすり抜ける。
fn 飾りの記号を外す(候補: &str) -> &str {
    候補.trim_matches(|文字| 飾りの記号一覧.contains(&文字))
}

/// 「の節」の直後が助詞か文末のときだけ節への参照とみなす。「節参照」のように節が複合語の
/// 一部をなす場合を、参照から除くための条件である。
fn 節が語末か(直後: &str) -> bool {
    直後.chars().next().is_none_or(|文字| 語末に続く文字一覧.contains(&文字))
}

fn 区切りまで遡る(前方: &str) -> String {
    let mut 開始 = 前方.len();
    for (位置, 文字) in 前方.char_indices().rev() {
        if 区切り文字一覧.contains(&文字) {
            break;
        }
        開始 = 位置;
    }
    前方[開始..].to_string()
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn 助詞形は区切りまで遡る() {
        assert_eq!(節名を抽出する("是正時は、既知の逸脱の節へ追記する。"), vec!["既知の逸脱".to_string()]);
    }

    #[test]
    fn 短い候補は指示語とみなして捨てる() {
        assert!(節名を抽出する("その節を指す記述も直す。").is_empty());
        assert!(節名を抽出する("以下の節を参照する。").is_empty());
    }

    #[test]
    fn 節が複合語の一部なら対象外() {
        assert!(節名を抽出する("規約適合の機械検査(参照パス実在・文書内の節参照実在)").is_empty());
    }

    #[test]
    fn 強調の記号が付いた指示語も捨てる() {
        assert!(節名を抽出する("。**この節が綴るのはこの第一形だけである**").is_empty());
        assert!(節名を抽出する("。*その節*を指す。").is_empty());
        assert!(節名を抽出する("。`この節`を指す。").is_empty());
    }

    #[test]
    fn 強調の記号が付いた節名は記号を外して読む() {
        assert_eq!(節名を抽出する("是正時は、**既知の逸脱**の節へ追記する。"), vec!["既知の逸脱".to_string()]);
        assert_eq!(節名を抽出する("是正時は、`既知の逸脱`の節へ追記する。"), vec!["既知の逸脱".to_string()]);
    }
}
