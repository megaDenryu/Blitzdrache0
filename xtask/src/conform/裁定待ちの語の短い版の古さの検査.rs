//! 裁定待ちの語の短い版(`_doc/計画/裁定待ちの語の短い定義.md`)が古くなっていないかの検査。元の一覧から短い版を組み直し、書かれている短い版と一致することを確かめる。
//! 元の一覧に読めない行があれば、その行を1件ずつ違反にする(黙って飛ばさない)。短い版が無いときと一致しないときは、生成のコマンドを案内する違反にする。
//! 組み直し方は生成のコマンドと同じ1つの実装(`xtask/src/裁定待ちの語の短い版.rs`)を使う。

use std::io::ErrorKind;

use super::error::規約検査の破れ;
use super::violation::違反;
use crate::裁定待ちの語の短い版::裁定待ちの語のファイル::裁定待ちの語のファイル;
use crate::裁定待ちの語の短い版::{生成のコマンド, 短い定義一覧を書けない理由};

pub fn 短い版が元の一覧と一致するかを検査する() -> Result<Vec<違反>, 規約検査の破れ> {
    let ファイル = 裁定待ちの語のファイル::リポジトリの根からの既定();
    let 元の一覧 = ファイル.元の一覧を読む().map_err(|誤り| 規約検査の破れ::ファイルを読めなかった(ファイル.裁定待ちの語の一覧のパス(), 誤り))?;
    let 生成した結果 = 元の一覧.短い版を組む();
    match 生成した結果.短い版を書いてよいかを確かめる() {
        Ok(()) => {}
        Err(短い定義一覧を書けない理由::読めない行がある(読めなかった行一覧)) => {
            return Ok(読めなかった行一覧
                .iter()
                .map(|行| 違反::行単位(ファイル.裁定待ちの語の一覧のパス().to_path_buf(), 行.行番号(), format!("裁定待ちの語として読めない行である: {}", 行.理由の説明())))
                .collect());
        }
        Err(理由 @ 短い定義一覧を書けない理由::語の数が合わない { .. }) => return Ok(vec![違反::ファイル単位(ファイル.裁定待ちの語の短い定義のパス().to_path_buf(), 理由.to_string())]),
    }
    let 書かれている短い版 = match ファイル.短い版を読む() {
        Ok(本文) => 本文,
        Err(誤り) if 誤り.kind() == ErrorKind::NotFound => {
            return Ok(vec![違反::ファイル単位(
                ファイル.裁定待ちの語の短い定義のパス().to_path_buf(),
                format!("裁定待ちの語の短い版が無い。`{生成のコマンド}` を実行して生成する"),
            )]);
        }
        Err(誤り) => return Err(規約検査の破れ::ファイルを読めなかった(ファイル.裁定待ちの語の短い定義のパス(), 誤り)),
    };
    Ok(生成した結果
        .短い版()
        .初めて食い違う行番号(&書かれている短い版)
        .map(|行番号| {
            違反::行単位(
                ファイル.裁定待ちの語の短い定義のパス().to_path_buf(),
                行番号,
                format!("裁定待ちの語の短い版が元の一覧から生成し直した結果と一致しない。`{生成のコマンド}` を実行して生成し直す"),
            )
        })
        .into_iter()
        .collect())
}
