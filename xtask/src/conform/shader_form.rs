//! シェーダーの原文に在るべき綴りと在ってはならない綴りの検査。受け取るのは無し(対象の綴りは台帳が持つ)、
//! 返すのは在るべき綴りが消えたファイルと、在ってはならない綴りが書き戻された行の違反一覧である。
//!
//! 守るのは「正典式のGPUの写しはCPU正本と同じ演算の順で書く」という判断1の契約のうち、値の一致(`shader_constant`)でも
//! 束縛の一致(`shader_binding`)でも捉えられない式の形である。式の形の違いは同じ入力の大半で同じ結果を出し、
//! 境界の1点でだけ結果が分かれるため、CPUの検査もGPUの参照比較も素通りする。
//! 綴りで固定するのは、その境界の1点を通す題材が実測に向かないためである(台帳の各項目が理由を持つ)。
//! 出現と数えるのはコメントでない行だけである。コメントでの言及を数えると、式を消しても「式に触れたコメント」1つで検査が通る。

mod table;

use std::path::{Path, PathBuf};

use super::error::規約検査の破れ;
use super::violation::違反;

pub fn 全シェーダーの原文の形を検査する() -> Result<Vec<違反>, 規約検査の破れ> {
    let mut 違反一覧 = Vec::new();
    for 契約 in &table::契約一覧 {
        let 内容 = std::fs::read_to_string(Path::new(契約.パス))
            .map_err(|誤り| 規約検査の破れ::ファイルを読めなかった(Path::new(契約.パス), 誤り))?;
        違反一覧.extend(ファイル1つを検査する(契約, &内容));
    }
    Ok(違反一覧)
}

fn ファイル1つを検査する(契約: &table::原文の形の契約, 内容: &str) -> Vec<違反> {
    let mut 違反一覧 = Vec::new();
    for 綴り in 契約.在るべき綴り一覧 {
        if !コメントでない行に現れるか(内容, 綴り) {
            違反一覧.push(違反::ファイル単位(
                PathBuf::from(契約.パス),
                format!("在るべき綴り「{綴り}」がコメントでない行に無い({})", 契約.守るもの),
            ));
        }
    }
    for (行番号, 行) in 内容.lines().enumerate() {
        for 綴り in 契約.在ってはならない綴り一覧 {
            if !コメント行か(行) && 行.contains(綴り) {
                違反一覧.push(違反::行単位(
                    PathBuf::from(契約.パス),
                    行番号 + 1,
                    format!("在ってはならない綴り「{綴り}」を書き戻している({})", 契約.守るもの),
                ));
            }
        }
    }
    違反一覧
}

fn コメント行か(行: &str) -> bool {
    行.trim_start().starts_with("//")
}

fn コメントでない行に現れるか(内容: &str, 綴り: &str) -> bool {
    内容.lines().any(|行| !コメント行か(行) && 行.contains(綴り))
}

#[cfg(test)]
mod tests {
    use super::*;

    const 契約: table::原文の形の契約 = table::原文の形の契約 {
        パス: "shaders/検査.slang",
        在るべき綴り一覧: &["float v = wrap(a);"],
        在ってはならない綴り一覧: &["if (abs(v) > pi)"],
        守るもの: "検査",
    };

    #[test]
    fn 在るべき綴りがコードの行に在り在ってはならない綴りが無ければ違反にしない() {
        assert!(ファイル1つを検査する(&契約, "// if (abs(v) > pi) は書かない\n    float v = wrap(a);\n").is_empty());
    }

    #[test]
    fn 在るべき綴りがコメントにしか無ければ違反にする() {
        assert_eq!(ファイル1つを検査する(&契約, "// float v = wrap(a);\n    float v = a;\n").len(), 1);
    }

    #[test]
    fn 在ってはならない綴りを書き戻した行を違反にする() {
        let 違反一覧 = ファイル1つを検査する(&契約, "    float v = wrap(a);\n    if (abs(v) > pi)\n");
        assert_eq!(違反一覧.len(), 1);
        assert_eq!(違反一覧[0].行番号, Some(2));
    }
}
