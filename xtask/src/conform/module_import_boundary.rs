//! 取り込みを閉じたモジュールが、台帳の許した1箇所からしか取り込まれていないことの検査。
//! 受け取るのは1つのSlangファイルのパスと内容、返すのは許されていない取り込みと再輸出の違反一覧である。
//!
//! Slangの取り込みは推移しないため、局所光の問い合わせが束縛先を再輸出しない限り消費側からは名前が見えない。
//! しかしその境界を守っているのは「材質のシェーダーが取り込んでいない」という現状だけであり、`import`を1行
//! 足すこと自体は型検査が許す。境界を機械で強制するには、この1行を足せないことをここが見る必要がある
//! (参照: `_doc/設計/クラスタ多光源と点光源の影.md`「第3段階の実装と検収の実測」)。
//!
//! 再輸出も同じ理由で見る。取り込んでよい1箇所が`__exported import`へ変わると、その1文字の違いで消費側へ
//! 名前が漏れ、取り込みの並びは台帳どおりのまま境界だけが消える。

mod table;

use std::path::{Path, PathBuf};

use super::violation::違反;
use table::{取り込みの境界, 境界一覧};

pub fn 検査する(パス: &Path, 内容: &str) -> Vec<違反> {
    let 正規化したパス = スラッシュ区切りにする(パス);
    let mut 違反一覧 = Vec::new();
    for (行番号, 行) in 内容.lines().enumerate() {
        let Some(取り込み) = 取り込みを読む(行) else {
            continue;
        };
        for 境界 in &境界一覧 {
            違反一覧.extend(境界を1つ確かめる(境界, &取り込み, &正規化したパス, 行番号 + 1));
        }
    }
    違反一覧
}

/// 1行が表す取り込み。モジュール名と、再輸出かどうかを持つ。
struct 取り込み {
    モジュール名: String,
    再輸出か: bool,
}

fn 境界を1つ確かめる(境界: &取り込みの境界, 取り込み: &取り込み, パス: &str, 行番号: usize) -> Vec<違反> {
    if 取り込み.モジュール名 != 境界.モジュール名 {
        return Vec::new();
    }
    let モジュール名 = 境界.モジュール名;
    if !境界.取り込んでよいファイル一覧.contains(&パス) {
        let 許す先 = 境界.取り込んでよいファイル一覧.join("・");
        return vec![違反::行単位(
            PathBuf::from(パス),
            行番号,
            format!("{モジュール名}を取り込んでよいのは{許す先}だけである。{}", 境界.閉じる理由),
        )];
    }
    if 取り込み.再輸出か && !境界.再輸出を許すか {
        return vec![違反::行単位(
            PathBuf::from(パス),
            行番号,
            format!("{モジュール名}を再輸出してはならない。再輸出すると、このモジュールを取り込んだ側の消費者へ束縛先の名前がそのまま見える"),
        )];
    }
    Vec::new()
}

/// 取り込みの行からモジュール名を取り出す。取り込みでない行は`None`を返す。
fn 取り込みを読む(行: &str) -> Option<取り込み> {
    let 整えた行 = 行.trim();
    let (再輸出か, 残り) = match 整えた行.strip_prefix("__exported ") {
        Some(残り) => (true, 残り),
        None => (false, 整えた行),
    };
    let 名前 = 残り.strip_prefix("import ")?.trim().strip_suffix(';')?.trim();
    if 名前.is_empty() {
        return None;
    }
    Some(取り込み {
        モジュール名: 名前.to_string(),
        再輸出か,
    })
}

/// GPU側の台帳がスラッシュ区切りで書かれているため、走査が返した区切りをそろえる。
fn スラッシュ区切りにする(パス: &Path) -> String {
    パス.to_string_lossy().replace('\\', "/")
}

