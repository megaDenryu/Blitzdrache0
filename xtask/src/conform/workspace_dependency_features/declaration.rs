//! ワークスペース依存の宣言: 根のCargo.tomlの依存節の1行が宣言する、既定機能を使うかと明示した機能の一覧。
//! 担当するのは行を読み取ることと、台帳の項と突き合わせて食い違いを述べることである。何が台帳の正しい値かは台帳の側が持つ。
//!
//! 分けているのは、依存を足すときに触るのが台帳だけであり、この読み取りの工程は触らないためである。
//! 触れる対象と変わる理由が別であることが分ける根拠である。

use super::feature_list::機能一覧を読む;
use super::ledger::機能台帳の項;

/// 既定機能を使わない宣言の綴り。Cargoが読むのはこの綴りだけであり、空白の詰め方が違えば別の意味になる。
const 既定機能を切る綴り: &str = "default-features = false";

/// 依存節の1行を読み取った結果。1行で閉じていない宣言を宣言でない行と同じに扱わないのは、
/// 機能一覧の一部だけを読んで合格を返す形になるためである。
pub(super) enum 依存節の行 {
    宣言でない,
    一行で閉じていない { 名前: String },
    宣言(ワークスペース依存の宣言),
}

impl 依存節の行 {
    pub(super) fn 読み取る(行: &str) -> Self {
        let 行 = 行.trim();
        if 行.is_empty() || 行.starts_with('#') || 行.starts_with('[') {
            return Self::宣言でない;
        }
        let Some(等号位置) = 行.find('=') else {
            return Self::宣言でない;
        };
        let 名前 = 行[..等号位置].trim();
        if 名前.is_empty() {
            return Self::宣言でない;
        }
        let 右辺 = 行[等号位置 + 1..].trim();
        if !右辺.starts_with('{') {
            return Self::宣言(ワークスペース依存の宣言::版だけの宣言から生成する(名前));
        }
        if !右辺.ends_with('}') {
            return Self::一行で閉じていない { 名前: 名前.to_string() };
        }
        Self::宣言(ワークスペース依存の宣言::表の宣言から生成する(名前, 右辺))
    }
}

/// 版だけを綴る形(`ash = "0.38"`)は、既定機能を使い機能を1つも明示していない宣言である。
pub(super) struct ワークスペース依存の宣言 {
    名前: String,
    既定機能を使うか: bool,
    明示した機能一覧: Vec<String>,
}

impl ワークスペース依存の宣言 {
    fn 版だけの宣言から生成する(名前: &str) -> Self {
        Self {
            名前: 名前.to_string(),
            既定機能を使うか: true,
            明示した機能一覧: Vec::new(),
        }
    }

    fn 表の宣言から生成する(名前: &str, 右辺: &str) -> Self {
        Self {
            名前: 名前.to_string(),
            既定機能を使うか: !右辺.contains(既定機能を切る綴り),
            明示した機能一覧: 機能一覧を読む(右辺),
        }
    }

    pub(super) fn 名前(&self) -> &str {
        &self.名前
    }

    /// 機能の並び順まで一致を求めるのは、台帳と宣言を目で突き合わせる者が並べ替えを追わずに済むためである。
    pub(super) fn 台帳と食い違う点一覧(&self, 項: &機能台帳の項) -> Vec<String> {
        let mut 食い違い一覧 = Vec::new();
        if self.既定機能を使うか != 項.既定機能を使うか {
            食い違い一覧.push(format!(
                "{}の既定機能の扱いが台帳と違う(台帳: {}、Cargo.toml: {})",
                self.名前,
                既定機能の綴り(項.既定機能を使うか),
                既定機能の綴り(self.既定機能を使うか)
            ));
        }
        if !self.明示した機能一覧.iter().map(String::as_str).eq(項.機能一覧.iter().copied()) {
            食い違い一覧.push(format!(
                "{}の機能一覧が台帳と違う(台帳: {:?}、Cargo.toml: {:?})",
                self.名前, 項.機能一覧, self.明示した機能一覧
            ));
        }
        食い違い一覧
    }
}

fn 既定機能の綴り(使うか: bool) -> &'static str {
    if 使うか { "既定機能を使う" } else { "既定機能を切る" }
}
