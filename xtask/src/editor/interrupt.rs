//! Ctrl+Cの割り込みを捕らえ、登録済みの子プロセスの木を終わらせてから自分を終える配線。
//! いつ呼ばれるか: `cargo xtask editor`が子を起動する前に1回だけ。
//!
//! 割り込みで`xtask`だけが消えると、開発サーバー(vite)が待ち受け口を掴んだまま残り、
//! 次の起動が番号の衝突で落ちる。この配線が無いと、通常の終了経路の後始末だけでは届かない。
//!
//! 注意: 強制終了(`TerminateProcess`。開発の道具がバックグラウンドのシェルを畳むときの止め方が
//! これに当たる)ではこの処理そのものが走らない。その止め方はWindowsの仕事の束が受け持つ
//! (参照: `kill_with_parent.rs`)。この配線は、Ctrl+Cで止めたときに何が起きたかを印字して即座に終わらせる
//! 役目を持ち、仕事の束を用意できなかった場合の後始末もここが担う。

use std::sync::Arc;

use super::shutdown_registry::停止台帳;

/// 割り込みの終了コード。128に割り込みの番号(2)を足す、Unixの慣習に合わせた値である。
const 割り込みで終わったときの終了コード: i32 = 130;

/// 割り込みを受けたときに走らせる後始末。無名の処理でなく名前の付いた型にしてあるのは、
/// 何に触るか(台帳)を構築時に明示するためである(参照: グローバルCLAUDE.md「デザインパターンの既定」)。
struct 割り込み時に木を全て終わらせる指令 {
    台帳: Arc<停止台帳>,
}

impl 割り込み時に木を全て終わらせる指令 {
    fn 実行する(&self) {
        println!("Ctrl+Cを受け取った。編集サーバーと開発サーバーを木ごと終わらせる。");
        self.台帳.登録済みの木を全て終わらせる();
        std::process::exit(割り込みで終わったときの終了コード);
    }
}

pub(crate) fn 割り込みを捕らえて台帳の木を終わらせるようにする(台帳: Arc<停止台帳>) {
    let 指令 = 割り込み時に木を全て終わらせる指令 { 台帳 };
    if let Err(原因) = ctrlc::set_handler(move || 指令.実行する()) {
        println!("Ctrl+Cの捕捉を登録できないまま起動する: {原因}");
        println!("Ctrl+Cで止めると子プロセスが残ることがある。残ったら Get-NetTCPConnection で番号を調べ、taskkill /T /F /PID <番号> で終わらせる。");
    }
}
