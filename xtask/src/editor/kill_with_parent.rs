//! 親のプロセスが消えたときに、起動した子孫をまとめて終わらせる最後の網。
//! いつ呼ばれるか: `cargo xtask editor`が子を起動する前に束を1つ作り、子を起動するたびにその束へ加える。
//!
//! 通常の終了・Ctrl+Cの割り込み・木ごとの終了は、どれも`xtask`自身の処理が走ることを前提にしている。
//! 強制終了(`TerminateProcess`。開発の道具がバックグラウンドのシェルを畳むときの止め方がこれに当たる)では
//! `xtask`の処理が1行も走らないため、その3つはどれも届かない。実測でも編集サーバーと開発サーバーの両方が残った。
//!
//! Windowsの仕事の束(Job Object)は、束への取っ手が全て閉じたときに中のプロセスを終わらせる設定を持てる。
//! 取っ手を握っているのは`xtask`自身であり、`xtask`がどんな終わり方をしてもOSが取っ手を閉じるため、
//! この設定だけはOSの側で効く。既存の3つの経路を置き換えるものではなく、その下に敷く。
//!
//! 前提: 仕事の束はWindowsの仕組みである。他のOSには対応する道具が無いため、そちらでは何もしない。

use super::process_tree::子プロセスの木;

/// 起動した子孫のうち、親のプロセスが消えたときに道連れにして終わらせる集まり。
/// 注意: この値を落とすと道連れの設定も切れる。`cargo xtask editor`が終わるまで持ち続けること。
pub(crate) struct 親と道連れに終わる子孫の束(道連れの仕掛け);

impl 親と道連れに終わる子孫の束 {
    pub(crate) fn 親が消えたら道連れにする設定で作る() -> Self {
        Self(道連れの仕掛け::用意する())
    }

    /// 起動した直後の木を加える。木の根を入れれば、根が後から起こす子孫も同じ束へ入るため、根だけを渡す。
    pub(crate) fn 木を道連れに加える(&self, 木: &子プロセスの木) {
        self.0.木を加える(木);
    }
}

/// 道連れを実現する仕掛け。用意できなかった場合に何もしない枝を持つのは、道連れが無くても編集サーバーと
/// 開発サーバーの起動そのものは成り立つためである。ここで起動を止めると、最後の網の不在が作業の停止になる。
#[cfg(windows)]
enum 道連れの仕掛け {
    仕事の束(win32job::Job),
    用意できなかった,
}

#[cfg(windows)]
impl 道連れの仕掛け {
    fn 用意する() -> Self {
        let mut 制限 = win32job::ExtendedLimitInfo::new();
        制限.limit_kill_on_job_close();
        match win32job::Job::create_with_limit_info(&制限) {
            Ok(束) => Self::仕事の束(束),
            Err(原因) => {
                println!("親が消えたときに子孫を道連れにする仕事の束を用意できないまま起動する: {原因}");
                println!("強制終了で止めると編集サーバーと開発サーバーが残る。残ったら taskkill /T /F /PID <番号> で終わらせる。");
                Self::用意できなかった
            }
        }
    }

    fn 木を加える(&self, 木: &子プロセスの木) {
        let Self::仕事の束(束) = self else { return };
        let Some(取っ手の番地) = 木.子への取っ手の番地() else {
            println!("子への取っ手の番地が符号付きの範囲へ収まらないため、道連れの束へ加えられない。");
            return;
        };
        if let Err(原因) = 束.assign_process(取っ手の番地) {
            println!("起動した子を道連れの束へ加えられない: {原因}");
        }
    }
}

/// 仕事の束を持たないOS向けの仕掛け。何もしないことが正しい振る舞いであり、後始末は既存の3つの経路が担う。
#[cfg(not(windows))]
struct 道連れの仕掛け;

#[cfg(not(windows))]
impl 道連れの仕掛け {
    fn 用意する() -> Self {
        Self
    }

    fn 木を加える(&self, _木: &子プロセスの木) {}
}
