//! `building-outline-catalog`コマンド: 実際の部品を展開して、編集画面用の版付き建物外形カタログを書き出す。
//! `editor`コマンドが起動の前提としてこの書き出しを呼ぶため、`editor`の子モジュールとして置く。
//!
//! 宣言の規則5件と、編集データの置き場に並ぶベイ格子の両方を1つのカタログへ合流させる。格子の台帳を先に
//! 読むのは、格子が1件でも解けないときにカタログを書き換えないためである。
//!
//! 外部アセットの置き場が無い環境では、建物定義0件の版付きカタログを書いて診断を印字する。
//! ここで失敗させると、外部アセットを持たない環境で編集サーバーそのものが起動できなくなる。
//!
//! 格子の置き場を引数のプロジェクトルートから作るのは、編集サーバーが`--project`で開くのと同じ置き場を
//! 読むためである。リポジトリルート固定にすると、使い捨てのプロジェクトを開いた実行がリポジトリ側の格子で
//! カタログを組み、画面に出る建物と保存先の建物が食い違う。カタログのファイルの位置はリポジトリルート側であり、
//! 編集サーバーが読む位置(`repository_root.rs`)と揃えている。

use std::path::{Path, PathBuf};

use blitz_asset_compiler::{
    建物の格子の置き場, 建物外形カタログのファイル, 建物外形カタログの組み立て係, 建物外形カタログエラー, 空の建物外形カタログを作る,
};

use super::project_root::プロジェクトルート;

pub fn 建物外形カタログを書き出す(引数一覧: &[String]) -> Result<(), String> {
    let リポジトリルート = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let プロジェクトルート = プロジェクトルート::引数から解く(引数一覧, &リポジトリルート);
    let 出力 = 既定のファイルへ書き出す(&リポジトリルート, &プロジェクトルート)?;
    println!("建物外形カタログ: {}", 出力.display());
    Ok(())
}

pub(crate) fn 既定のファイルへ書き出す(
    リポジトリルート: &Path, プロジェクトルート: &プロジェクトルート
) -> Result<PathBuf, String> {
    let ファイル = 建物外形カタログのファイル::リポジトリルートから生成する(リポジトリルート);
    let 出力 = ファイル.パス().to_path_buf();
    let 置き場 = 建物の格子の置き場::プロジェクトルートから生成する(プロジェクトルート.パス());
    let 組み立て係 = 建物外形カタログの組み立て係::置き場から台帳を読んで生成する(&置き場).map_err(|原因| 原因.to_string())?;
    println!("建物の格子: {}件({})", 組み立て係.格子の台帳().件数(), 置き場.パス().display());
    let カタログ = match 組み立て係.組み立てる() {
        Ok(カタログ) => カタログ,
        Err(建物外形カタログエラー::外部ソースルート不在(診断)) => {
            println!("外部アセットの置き場が無いため、建物定義の生成をスキップする: {診断}");
            空の建物外形カタログを作る()
        }
        Err(原因) => return Err(原因.to_string()),
    };
    ファイル.書き出す(&カタログ).map_err(|原因| 原因.to_string())?;
    Ok(出力)
}
