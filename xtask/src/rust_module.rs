//! Rustのファイルの配置とモジュールの対応。`x/mod.rs`はディレクトリ`x`のモジュールの本体であり、
//! `x/y.rs`はモジュール`y`の本体で、その子のモジュールは`x/y/`配下に置かれる。
//!
//! この対応は2つの検査が使う。型ごとの分量の計測はimplブロックが綴った経路から実装対象の定義ファイルを
//! 引き当てるために使い、自由関数の検査は親の型のモジュールの木にそのファイルが属するかを判定するために使う。
//! どちらの検査にも属さない知識であるため、ここが持つ。

mod module_directory;
mod module_position;

pub use module_directory::モジュールのディレクトリ;
