//! 場所巡りの世界がどの乱数の種から作られたかを読む工程。担当するのは、読めなかったことを黙って埋めずに返すことだけであり、
//! 読めた種をどう見せるかは呼び出し側が決める。
//!
//! この読み口を置くのは、`cargo xtask game-fox-tour`が検収の種で場所巡りの世界を作り直すため、別の種で作ったマップが
//! 検収を1度走らせただけで黙って入れ替わるからである。遊ぶ前にどの種の生成物かが分かれば、入れ替わりに気づかないまま遊ぶことがなくなる。
//!
//! 置き場もファイル名もアセットコンパイラの`場所巡りの世界のソースディレクトリ`が持つ。ここが綴りの写しを持たないのは、
//! 書き手と読み手で綴りが食い違うと「種が分からない」を出し続ける沈黙の劣化になるためである。

use std::path::PathBuf;

use blitz_asset_compiler::{ソースルート, 場所巡りの世界のソースディレクトリ};

/// 生成器が書き出す先のソースルート。リポジトリルートからの相対で書くのは、xtaskの全コマンドがリポジトリルートを
/// 作業ディレクトリとして走るためである。
const 既定のソースルート: &str = "assets";

/// 乱数の種をファイルから読んだ結果。読めなかったことを空の綴りへ潰さず、事情を持たせたまま呼び出し側へ運ぶ。
pub enum 乱数の種の読み取り結果 {
    /// ファイルから読めた種の10進表記。
    読めた種(String),
    /// 読めなかった事情を人が読める1文にしたもの。
    読めなかった事情(String),
}

pub fn 場所巡りの世界の生成に使った乱数の種を読む() -> 乱数の種の読み取り結果 {
    let ソースルート = ソースルート::生成する(PathBuf::from(既定のソースルート));
    let 置き場 = match 場所巡りの世界のソースディレクトリ::ソースルートの下を開く(&ソースルート) {
        Ok(置き場) => 置き場,
        Err(誤り) => return 乱数の種の読み取り結果::読めなかった事情(誤り.to_string()),
    };
    match 置き場.生成に使った乱数の種を読む() {
        Ok(中身) => 読めた綴りを種として受け取る(&中身),
        Err(事情) => 乱数の種の読み取り結果::読めなかった事情(事情),
    }
}

fn 読めた綴りを種として受け取る(中身: &str) -> 乱数の種の読み取り結果 {
    let 種 = 中身.trim();
    if 種.is_empty() {
        return 乱数の種の読み取り結果::読めなかった事情("種を書いたファイルが空である".to_string());
    }
    乱数の種の読み取り結果::読めた種(種.to_string())
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    /// 書き手と読み手でファイル名の綴りが食い違うと、遊ぶ入口が黙って「種が分からない」を出し続ける。
    /// リポジトリへ収めた世界の種が読めることで、置き場の型を通した参照が実際に届いていることを確かめる。
    #[test]
    fn リポジトリへ収めた場所巡りの世界の種が読める() {
        let リポジトリルート = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let ソースルート = ソースルート::生成する(リポジトリルート.join(既定のソースルート));
        let 置き場 = 場所巡りの世界のソースディレクトリ::ソースルートの下を開く(&ソースルート).unwrap();
        let 乱数の種の読み取り結果::読めた種(種) = 読めた綴りを種として受け取る(&置き場.生成に使った乱数の種を読む().unwrap())
        else {
            panic!("リポジトリへ収めた場所巡りの世界から種を読めなかった");
        };
        assert!(種.parse::<u32>().is_ok(), "種が32ビットの非負整数として読めない: {種}");
    }

    #[test]
    fn 空の綴りを種として受け取らない() {
        assert!(matches!(
            読めた綴りを種として受け取る("  \n"),
            乱数の種の読み取り結果::読めなかった事情(_)
        ));
    }
}
