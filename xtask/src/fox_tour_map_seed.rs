//! 場所巡りの世界がどの乱数の種から作られたかをファイルから読む工程。担当するのは読み出し先のパスと、
//! 読めなかったことを黙って埋めずに返すことだけであり、読めた種をどう見せるかは呼び出し側が決める。
//!
//! この読み口を置くのは、`cargo xtask game-fox-tour`が検収の種でassets/fox_tour_world/を作り直すため、
//! 別の種で作ったマップが検収を1度走らせただけで黙って入れ替わるからである。遊ぶ前にどの種の生成物かが
//! 分かれば、入れ替わりに気づかないまま遊ぶことがなくなる。
//!
//! 書き手は`crates/blitz_asset_compiler/examples/generate_source_assets/fox_tour_world/seed_file.rs`であり、
//! ファイル名の綴りは向こうにも同じものがある。実行時形式は同じソースアセットから焼いた導出物であるため、
//! ソースアセットに添えた種が遊ぶ世界の種と一致する。

use std::path::Path;

/// 生成器が種を書き出す先。リポジトリルートからの相対で書くのは、xtaskの全コマンドがリポジトリルートを
/// 作業ディレクトリとして走るためである。
const 種を書き出したファイルのパス: &str = "assets/fox_tour_world/map_seed.txt";

/// 乱数の種をファイルから読んだ結果。読めなかったことを空の綴りへ潰さず、事情を持たせたまま呼び出し側へ運ぶ。
pub enum 乱数の種の読み取り結果 {
    /// ファイルから読めた種の10進表記。
    読めた種(String),
    /// 読めなかった事情を人が読める1文にしたもの。
    読めなかった事情(String),
}

pub fn 場所巡りの世界の生成に使った乱数の種を読む() -> 乱数の種の読み取り結果 {
    指定したファイルから乱数の種を読む(Path::new(種を書き出したファイルのパス))
}

fn 指定したファイルから乱数の種を読む(パス: &Path) -> 乱数の種の読み取り結果 {
    let 中身 = match std::fs::read_to_string(パス) {
        Ok(中身) => 中身,
        Err(誤り) => {
            return 乱数の種の読み取り結果::読めなかった事情(format!("{}を読めなかった: {誤り}", パス.display()));
        }
    };
    let 種 = 中身.trim();
    if 種.is_empty() {
        return 乱数の種の読み取り結果::読めなかった事情(format!("{}に種が書かれていない", パス.display()));
    }
    乱数の種の読み取り結果::読めた種(種.to_string())
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    /// 書き手と読み手でファイル名の綴りが食い違うと、遊ぶ入口が黙って「種が分からない」を出し続ける。
    /// リポジトリへ収めた世界の種が読めることで、2箇所の綴りが一致していることを確かめる。
    #[test]
    fn リポジトリへ収めた場所巡りの世界の種が読める() {
        let パス = Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join(種を書き出したファイルのパス);
        let 乱数の種の読み取り結果::読めた種(種) = 指定したファイルから乱数の種を読む(&パス) else {
            panic!("{}から種を読めなかった", パス.display());
        };
        assert!(種.parse::<u32>().is_ok(), "種が32ビットの非負整数として読めない: {種}");
    }

    #[test]
    fn ファイルが無ければ事情を返す() {
        let パス = Path::new(env!("CARGO_MANIFEST_DIR")).join("存在しないファイル.txt");
        assert!(matches!(
            指定したファイルから乱数の種を読む(&パス),
            乱数の種の読み取り結果::読めなかった事情(_)
        ));
    }
}
