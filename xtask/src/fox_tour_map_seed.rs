//! 場所巡りの世界の決定性検収に使う乱数の種と、実際に遊ぶ世界の乱数の種の読み取りをまとめる。

use blitz_asset_compiler::マップ生成の乱数の種;

pub const 決定性検収の乱数の種: マップ生成の乱数の種 = マップ生成の乱数の種::生成する(20260810);

pub enum 乱数の種の読み取り結果 {
    読めた種(u32),
    読めなかった事情(String),
}

pub fn 場所巡りの世界の生成に使った乱数の種を読む() -> 乱数の種の読み取り結果 {
    let 出力ルート = crate::fox_tour_launch::場所巡りの世界を遊ぶ実行時形式の出力ルート();
    match 出力ルート.世界の乱数の種を読む() {
        Ok(Some(種)) => 乱数の種の読み取り結果::読めた種(種.値()),
        Ok(None) => 乱数の種の読み取り結果::読めなかった事情("実行時カタログが乱数の種による世界ではない".to_string()),
        Err(誤り) => 乱数の種の読み取り結果::読めなかった事情(誤り.to_string()),
    }
}
