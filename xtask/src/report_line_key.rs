//! 報告の1行の中に並ぶ鍵。綴りと、その鍵に値が結ばれる形を私有し、続く語の取り出しだけを外へ出す。
//!
//! 見出しと分けるのは、置かれる場所が違うためである。見出しは行の先頭に立ち、鍵は行の途中に並ぶ。
//! 1つの型で兼ねると、行の先頭を探す照合へ行の途中の綴りを渡した入口が型を通り、その入口だけが静かに読めなくなる。
//!
//! 結ばれる形を枝で数え上げるのは、報告の行によって値の置き方が違うためである。実測では
//! 「鍵 値」「鍵=値」「鍵に括弧が触れた語の次」「鍵で始まる語の残り」の4通りが入口ごとに手で書かれていた。

use std::borrow::Cow;
use std::fmt;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 報告の行の鍵(Cow<'static, str>);

/// 鍵に値が結ばれる形。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 鍵に値が結ばれる形 {
    /// 「鍵 値」。空白で切った語が鍵と一致し、その次の語が値である。
    次の語が値である,
    /// 「(p50 0.09」のように区切りが鍵へ触れている表。鍵で終わる語の次の語が値である。
    この綴りで終わる語の次が値である,
    /// 「標本60)」のように鍵と値が1語に続いている表。鍵の後ろの残りが値である。
    この綴りに続く残りが値である,
    /// 「全画素921600、最大差0.5」のように読点で区切り、鍵と値と次の鍵が空白なしで連なる行。
    /// 鍵の後ろに続く数字の並びが値である。
    この綴りに続く数字の並びが値である,
    /// 「鍵=値」。
    等号の後ろが値である,
}

impl 報告の行の鍵 {
    pub const fn 定数から生成する(綴り: &'static str) -> Self {
        Self(Cow::Borrowed(綴り))
    }

    /// 実行時に組み立てた綴りから作る。区間名やパス名を含む鍵がこの口を通る。
    pub fn 組み立てた綴りから生成する(綴り: String) -> Self {
        Self(Cow::Owned(綴り))
    }

    /// この鍵に結ばれた値の語を探す。鍵が無いことと、鍵はあるが値が無いことを別の枝で返す。
    pub fn 結ばれた語を探す<'行>(&self, 行: &'行 str, 形: 鍵に値が結ばれる形) -> 鍵に結ばれた語の在り処<'行> {
        match 形 {
            鍵に値が結ばれる形::次の語が値である => self.語の次を探す(行, |語| 語 == self.0.as_ref()),
            鍵に値が結ばれる形::この綴りで終わる語の次が値である => {
                self.語の次を探す(行, |語| 語.ends_with(self.0.as_ref()))
            }
            鍵に値が結ばれる形::この綴りに続く残りが値である => self.語の残りを探す(行, self.0.as_ref()),
            鍵に値が結ばれる形::この綴りに続く数字の並びが値である => self.続く数字の並びを探す(行),
            鍵に値が結ばれる形::等号の後ろが値である => self.語の残りを探す(行, &format!("{}=", self.0)),
        }
    }

    /// 鍵の後ろに続く数字の並び。語の切れ目でなく数字でない文字で止めるのは、読点で区切る行が
    /// 「全画素921600、1画素の幅0.001389を超えた画素0」のように鍵と値と次の鍵を1語へ連ねるためである。
    fn 続く数字の並びを探す<'行>(&self, 行: &'行 str) -> 鍵に結ばれた語の在り処<'行> {
        let Some((_, 鍵の後ろ)) = 行.split_once(self.0.as_ref()) else {
            return 鍵に結ばれた語の在り処::鍵が無い;
        };
        let 桁数 = 鍵の後ろ.chars().take_while(|文字| 文字.is_ascii_digit() || *文字 == '.').count();
        if 桁数 == 0 {
            return 鍵に結ばれた語の在り処::鍵に値が続いていない;
        }
        鍵に結ばれた語の在り処::見つかった(&鍵の後ろ[..桁数])
    }

    fn 語の次を探す<'行>(&self, 行: &'行 str, 一致か: impl Fn(&str) -> bool) -> 鍵に結ばれた語の在り処<'行> {
        let mut 語一覧 = 行.split_whitespace().skip_while(|語| !一致か(語));
        if 語一覧.next().is_none() {
            return 鍵に結ばれた語の在り処::鍵が無い;
        }
        語一覧
            .next()
            .map_or(鍵に結ばれた語の在り処::鍵に値が続いていない, 鍵に結ばれた語の在り処::見つかった)
    }

    fn 語の残りを探す<'行>(&self, 行: &'行 str, 接頭辞: &str) -> 鍵に結ばれた語の在り処<'行> {
        行.split_whitespace()
            .find_map(|語| 語.strip_prefix(接頭辞))
            .map_or(鍵に結ばれた語の在り処::鍵が無い, 鍵に結ばれた語の在り処::見つかった)
    }
}

/// 鍵に結ばれた語を探した結果。1つの`Option`へ潰すと、どちらの側の書式が変わったのかを読み手が決められない。
pub enum 鍵に結ばれた語の在り処<'行> {
    見つかった(&'行 str),
    鍵が無い,
    鍵に値が続いていない,
}

impl fmt::Display for 報告の行の鍵 {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}
