//! 反証済みの件数と、検証した命題の件数から合否を決める判断を固定する試験。
//!
//! `ExitCode` は `PartialEq` を持たないため、終了コードそのものを比べない。合否の判断を
//! `設計の検証の合否` の選択肢へ切り出し、その選択肢を比べる。終了コードへ写すメソッドはその型の1箇所だけである。
//! **未決定が合否へどう効くかをこの試験は固定しない。** 未決定を失敗として扱うか警告として扱うかは
//! 命題の重要度によって分かれる判断であり、Issue #175 の設計の受理が決める。ここで「未決定は常に合格である」を
//! 固定すると、#175 がまだ下していない裁定を試験が先取りすることになる。
//! **反証済みなら不合格である側は固定する。** こちらを固定しないと、反証済みの退行を試験が捕まえられなくなる。
//! **命題を1件も検証しなかった実行は合格にしない。** これは受理の規則ではなく、検査器が1件も検査していない実行を
//! 合格として答えないという別の規約である。命題の集合が空になった事故が検証に通った状態と見分けられなくなる。

use super::{結果の件数, 設計の検証の合否};

#[test]
fn 反証済みが1件でもあれば不合格を答える() {
    let 件数 = 結果の件数 {
        証明済み: 3, 反証済み: 1, 未決定: 0
    };
    assert_eq!(件数.合否を答える(), 設計の検証の合否::反証済みが在る);
}

#[test]
fn 反証済みが1件でもあれば未決定が在っても不合格を答える() {
    let 件数 = 結果の件数 {
        証明済み: 0, 反証済み: 1, 未決定: 2
    };
    assert_eq!(件数.合否を答える(), 設計の検証の合否::反証済みが在る);
}

#[test]
fn 件数が3つとも0件のときは検証した命題が1件も無いを答える() {
    assert_eq!(結果の件数::default().合否を答える(), 設計の検証の合否::検証した命題が1件も無い);
}

#[test]
fn 証明済みが1件でもあれば合格を答える() {
    let 件数 = 結果の件数 {
        証明済み: 1, 反証済み: 0, 未決定: 0
    };
    assert_eq!(件数.合否を答える(), 設計の検証の合否::反証済みが1件も無い);
}
