//! 反証済みの件数と、検証した命題の件数から合否を決める判断を固定する試験。
//!
//! `ExitCode` は `PartialEq` を持たないため、終了コードそのものを比べない。合否の判断を
//! `設計の検証の合否` の選択肢へ切り出し、その選択肢を比べる。終了コードへ写す口はその型の1箇所だけである。
//! **未決定は不合格にしない**(Issue #173 の設計判断)。未決定で終了コードを非0にすると、
//! 検証器が解けなかった命題と設計が破れた命題が同じ失敗へ潰れる。
//! **命題を1件も検証しなかった実行は合格にしない。**検証していないことを合格として答えると、
//! 命題の集合が空になった事故が検証に通った状態と見分けられない。

use super::{結末の件数, 設計の検証の合否};

#[test]
fn 反証済みが1件でもあれば不合格を答える() {
    let 件数 = 結末の件数 {
        証明済み: 3, 反証済み: 1, 未決定: 0
    };
    assert_eq!(件数.合否を答える(), 設計の検証の合否::反証済みが在る);
}

#[test]
fn 反証済みが0件で未決定が在るときは合格を答える() {
    let 件数 = 結末の件数 {
        証明済み: 0, 反証済み: 0, 未決定: 2
    };
    assert_eq!(件数.合否を答える(), 設計の検証の合否::反証済みが1件も無い);
}

#[test]
fn 件数が3つとも0件のときは検証した命題が1件も無いを答える() {
    assert_eq!(結末の件数::default().合否を答える(), 設計の検証の合否::検証した命題が1件も無い);
}

#[test]
fn 証明済みが1件でもあれば合格を答える() {
    let 件数 = 結末の件数 {
        証明済み: 1, 反証済み: 0, 未決定: 0
    };
    assert_eq!(件数.合否を答える(), 設計の検証の合否::反証済みが1件も無い);
}
