mod 裁定を待つ母集団の案;
#[path = "設計関係への参加の計測/計測の表示.rs"]
mod 計測の表示;
#[cfg(test)]
#[path = "設計関係への参加の計測/設計関係への参加の計測の試験.rs"]
mod 設計関係への参加の計測の試験;

use blitz_design_verification::関係を落とした抽出の欠落;

use crate::design_model::{抽出した設計関係グラフと抽出の欠け, 設計概念への参照, 設計関係グラフ};

use 裁定を待つ母集団の案::{母集団の案, 母集団を採った内訳};

/// 母集団の案ごとの計測と、その数を読むために要る抽出の欠落の件数を1つにしたもの。
#[derive(Debug, Clone)]
pub struct 設計関係への参加の計測 {
    欠落: 関係を落とした抽出の欠落,
    保証範囲の外の構文の件数: usize,
    案ごとの計測一覧: Vec<案ごとの計測>,
}

/// 1つの母集団の案について数えた結果。
#[derive(Debug, Clone)]
pub struct 案ごとの計測 {
    案: 母集団の案,
    母集団の件数: usize,
    内訳: 母集団を採った内訳,
    参加していない概念一覧: Vec<参加していない概念>,
}

/// 母集団に入りながら、設計関係の辺を1本も持たないと数えた概念1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 参加していない概念 {
    参照: 設計概念への参照,
    理由: 参加していない理由,
}

/// その概念を参加していないと数えた理由。どれも設計関係の辺が1本も無く、参加に数えない2つ(保持する関係の辺と分類の事実)のどちらに現れるかだけが違う。
/// 参加に数えないものへの現れ方を分けて示すのは、母集団を裁定する人が「フィールドに持つだけの型」と「マーカーを実装しただけの型」を見分けられるようにするためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 参加していない理由 {
    保持する関係の辺にも分類の事実にも現れない, // 主語としても目的語としても辺が無く、マーカーの実装にも上位トレイトの宣言にも現れない
    保持する関係の辺にだけ現れる,               // 保持する関係の主語か目的語であるが、分類の事実には現れない
    分類の事実にだけ現れる,                     // マーカーを実装した型か、マーカーの実装と上位トレイトの宣言に現れるトレイトであるが、保持する関係の辺は無い
    保持する関係の辺と分類の事実の両方に現れる, // 保持する関係の主語か目的語であり、分類の事実にも現れる
}

impl 設計関係への参加の計測 {
    /// 抽出した設計関係グラフを、裁定を待つ2つの案で数える。欠落は入口が既に写したものを受け取り、同じ写しを2度作らない。
    pub fn 計測する(抽出したもの: &抽出した設計関係グラフと抽出の欠け, 欠落: &関係を落とした抽出の欠落) -> Self {
        Self {
            欠落: 欠落.clone(),
            保証範囲の外の構文の件数: 抽出したもの.保証範囲の外の構文の件数(),
            案ごとの計測一覧: 母集団の案::裁定を待つ2つの案().into_iter().map(|案| 案.グラフで数える(&抽出したもの.グラフ)).collect(),
        }
    }
}

impl 案ごとの計測 {
    /// 参加していない概念のうち、定義をたどれずモジュールパスが空の節点の件数。検証器はこの節点を反例として答えず未決定を答える。
    fn 参加していない概念のうちモジュールパスが空の節点の件数(&self) -> usize {
        self.参加していない概念一覧.iter().filter(|概念| 概念.参照.識別子().Rustの項目でありながら定義をたどれていないか()).count()
    }
}

impl 参加していない理由 {
    /// 4つの理由を表示の順に並べた全件。
    const fn 全部の一覧() -> [Self; 4] {
        [
            Self::保持する関係の辺にも分類の事実にも現れない,
            Self::保持する関係の辺にだけ現れる,
            Self::分類の事実にだけ現れる,
            Self::保持する関係の辺と分類の事実の両方に現れる,
        ]
    }

    /// その概念が設計関係の辺を1本も持たないなら理由を答え、持つなら何も答えない。保持する関係の辺と分類の事実のどちらに現れるかで理由を分ける。
    fn グラフに尋ねる(グラフ: &設計関係グラフ, 参照: &設計概念への参照) -> Option<Self> {
        if !グラフ.関係へ1つも参加していないか(参照) {
            return None;
        }
        let 保持する関係の端点か = グラフ.保持する関係一覧().iter().any(|関係| &関係.主語 == 参照 || &関係.目的語 == 参照);
        Some(match (保持する関係の端点か, グラフ.分類を貸す().事実に現れるか(参照)) {
            (false, false) => Self::保持する関係の辺にも分類の事実にも現れない,
            (true, false) => Self::保持する関係の辺にだけ現れる,
            (false, true) => Self::分類の事実にだけ現れる,
            (true, true) => Self::保持する関係の辺と分類の事実の両方に現れる,
        })
    }
}
