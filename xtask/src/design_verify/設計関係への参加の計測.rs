//! 設計関係へ参加していない概念の計測(Issue #187 の作業D・Issue #175 の Phase 9 の1の前段)。
//!
//! 「すべてのドメイン概念は、少なくとも1つの設計関係へ参加する」という全称の命題を検証へ接続する前に、
//! その命題の母集団をどう定めるかをオーナーが裁定する。この計測は、その裁定の材料として母集団の案ごとの数を出す。
//! **この計測は命題へ接続しない。** 検証の合否にも終了コードにも効かない。母集団の定義がまだ裁定されていないためである。
//!
//! **数えるのは、欠落による弱めを掛ける前の数である。** 構造の検証器は、抽出の欠落が1件でも在ると
//! 「参加していない」という答えを未決定へ落とす(`blitz_design_verification` の `不在に由来する結果を弱める`)。
//! したがって本番の命題の答えからはこの数を読めず、この計測は設計関係グラフへ直接尋ねて数える。
//! あわせて欠落の件数を出すのは、読み手が「欠落が何件在るから、本番の命題は反証を出せない」と読めるようにするためである。
//! 参照: `_doc/設計/設計オントロジー.md` 第7節・第9節。

#[path = "設計関係への参加の計測/裁定を待つ母集団の案.rs"]
mod 裁定を待つ母集団の案;
#[path = "設計関係への参加の計測/計測の表示.rs"]
mod 計測の表示;
#[cfg(test)]
#[path = "設計関係への参加の計測/設計関係への参加の計測の試験.rs"]
mod 設計関係への参加の計測の試験;

use blitz_design_verification::関係を落とした抽出の欠落;

use crate::design_model::{抽出した設計関係グラフと抽出の欠け, 設計概念への参照};

use 裁定を待つ母集団の案::母集団の案;

/// 母集団の案ごとの計測と、その数を読むために要る抽出の欠落の件数を1つにしたもの。
#[derive(Debug, Clone)]
pub struct 設計関係への参加の計測 {
    欠落: 関係を落とした抽出の欠落,
    保証範囲の外の構文の件数: usize,
    案ごとの計測一覧: Vec<案ごとの計測>,
}

/// 1つの母集団の案について数えた結果。
#[derive(Debug, Clone)]
pub struct 案ごとの計測 {
    案: 母集団の案,
    母集団の件数: usize,
    参加していない概念一覧: Vec<参加していない概念>,
}

/// 母集団に入りながら、その案の数え方で設計関係へ参加していないと数えた概念1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 参加していない概念 {
    参照: 設計概念への参照,
    理由: 参加していない理由,
}

/// その概念を参加していないと数えた理由。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 参加していない理由 {
    /// 主語としても目的語としても、辺が1本も無い。
    辺が1本も無い,
    /// 触れる辺は在るが、どれも設計解釈マーカーを目的語に取る `下位型である` の辺である。案2だけがこの理由を答える。
    マーカーへの下位型であるの辺しか無い { 本数: usize },
}

impl 設計関係への参加の計測 {
    /// 抽出した設計関係グラフを、裁定を待つ3つの案で数える。欠落は入口が既に写したものを受け取り、同じ写しを2度作らない。
    pub fn 計測する(抽出したもの: &抽出した設計関係グラフと抽出の欠け, 欠落: &関係を落とした抽出の欠落) -> Self {
        Self {
            欠落: 欠落.clone(),
            保証範囲の外の構文の件数: 抽出したもの.保証範囲の外の構文の件数(),
            案ごとの計測一覧: 母集団の案::裁定を待つ3つの案().into_iter().map(|案| 案.グラフで数える(&抽出したもの.グラフ)).collect(),
        }
    }
}
