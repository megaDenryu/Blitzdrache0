//! 処理の使い方とは、存在理由の公理が、処理が型をどう使えばその型が処理に使われたと数えるかを表す値のことである。
//! 受け取るのは束縛した概念、返すのは処理のどれかがその使い方で概念を使うという存在の命題である。
//! 公理の一覧(`structural_law.rs`)は、対象の型と容器の型のそれぞれにこの値を1つ持たせ、命題の組み立てはこの型へ任せる。

use blitz_design_verification::{原子命題, 命題, 対象集合, 束縛変数, 設計関係の種類, 非空の命題一覧, 項};

/// 処理が型をどう使えば、その型が処理に使われたと数えるか。
#[derive(Clone, Copy)]
pub enum 処理の使い方 {
    関係を張る(設計関係の種類),     // 処理がその型へその種類の関係を張る
    消費して次の状態として生成する, // ある1つの処理がその型を消費し、かつ次の状態として生成する。状態から値を取り出すだけの射影はこれに当たらない
}

impl 処理の使い方 {
    /// 処理のどれかがこの使い方で束縛した概念を使うという存在の命題。
    pub fn 処理が使う(self, 概念: &束縛変数) -> 命題 {
        match self {
            Self::関係を張る(種類) => 処理が関係を張る(種類, 概念),
            Self::消費して次の状態として生成する => {
                let 処理 = 束縛変数::生成する(&format!("{}を消費して次の状態として生成する処理", 概念.名前()));
                let 関係 = |種類| {
                    命題::原子から組む(原子命題::設計関係が在る {
                        主語: 項::束縛変数(処理.clone()),
                        種類,
                        目的語: 項::束縛変数(概念.clone()),
                    })
                };
                let 本体 = 命題::連言(非空の命題一覧::先頭と残りから生成する(関係(設計関係の種類::消費する), vec![関係(設計関係の種類::生成する)]));
                命題::存在を組む(処理, 対象集合::全ての設計関係の主語(設計関係の種類::消費する), 本体)
            }
        }
    }
}

// その種類の関係の主語に立つ処理のどれかが、束縛した概念へその関係を直に張るという存在の命題。
fn 処理が関係を張る(種類: 設計関係の種類, 概念: &束縛変数) -> 命題 {
    let 処理 = 束縛変数::生成する(&format!("{}を{}処理", 概念.名前(), 種類.語()));
    let 原子 = 原子命題::設計関係が在る {
        主語: 項::束縛変数(処理.clone()),
        種類,
        目的語: 項::束縛変数(概念.clone()),
    };
    命題::存在を組む(処理, 対象集合::全ての設計関係の主語(種類), 命題::原子から組む(原子))
}
