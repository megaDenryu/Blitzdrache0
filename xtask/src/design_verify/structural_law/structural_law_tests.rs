//! 入口の2つの法則が、どの原子命題で書かれているかを命題の木から確かめる試験。
//!
//! **命題の `表記()` の文字列を照合しない。** 表記は人が読むための文であり、文言を変えただけで落ちる試験は
//! 守りたいもの(どの原子で問うか)と違う理由で落ちる。原子の選択肢を分解して見る。
//!
//! 下位型である法則が経路の原子で書かれていることは、実物と同じ2辺のグラフを検証して確かめる。
//! `impl M状態 for 非貫通の一細分の解の状態` と `trait M状態: M不変データ` の2辺だけを持ち直接の辺を1本も持たないため、
//! 直接の辺で問う形へ戻すとこのグラフでは反証済みになる。

use std::path::PathBuf;

use blitz_design_verification::{マーカーの名乗り方, 原子命題, 命題, 命題の検証器, 対象集合, 構造の検証器};

use crate::design_model::{抽出の出どころ, 抽出元の構文, 設計概念, 設計概念の識別子, 設計関係, 設計関係の種類, 設計関係グラフ};

use super::{マーカーの正本のモジュールパス, 下位型である法則を組む, 設計関係へ参加する法則を組む};

/// 設計解釈マーカーの正本の側の識別子。法則が目的語をこのモジュールパスで名指すため、試験のグラフも同じモジュールパスへ節点を置く。
fn マーカーの識別子(名前: &str) -> 設計概念の識別子 {
    設計概念の識別子::Rustの項目として生成する(マーカーの正本のモジュールパス, 名前)
}

fn 下位型である辺(主語: &設計概念の識別子, 目的語: &設計概念の識別子, 構文: 抽出元の構文) -> 設計関係 {
    設計関係 {
        主語: 主語.clone(),
        種類: 設計関係の種類::下位型である,
        目的語: 目的語.clone(),
        出どころ: 抽出の出どころ {
            パス: PathBuf::from("crates/blitz_sim/src/contact/non_penetration/substep_state.rs"),
            行番号: 1,
            構文,
        },
    }
}

/// `非貫通の一細分の解の状態 → M状態 → M不変データ` の2辺だけを持つグラフ。直接の辺 `非貫通の一細分の解の状態 → M不変データ` を持たない。
/// 1辺目はマーカーを実装した型の辺であり、法則の母集団はこの型1件になる。
fn 実装と上位トレイトが繋がったグラフ() -> 設計関係グラフ {
    let 解の状態 = 設計概念の識別子::Rustの項目として生成する("blitz_sim::contact::non_penetration::substep_state", "非貫通の一細分の解の状態");
    let 状態 = マーカーの識別子("M状態");
    let 不変データ = マーカーの識別子("M不変データ");
    設計関係グラフ::生成する(
        vec![
            設計概念::型として生成する("blitz_sim::contact::non_penetration::substep_state", "非貫通の一細分の解の状態"),
            設計概念::トレイトとして生成する(マーカーの正本のモジュールパス, "M状態"),
            設計概念::トレイトとして生成する(マーカーの正本のモジュールパス, "M不変データ"),
        ],
        vec![下位型である辺(&解の状態, &状態, 抽出元の構文::設計解釈マーカーの実装), 下位型である辺(&状態, &不変データ, 抽出元の構文::上位トレイトの宣言)],
    )
    .グラフ
}

#[test]
fn 下位型である法則は直接の辺でなく経路の原子で問う() {
    let 命題::全称 { 対象集合: 走る範囲, 本体, .. } = 下位型である法則を組む("M状態", "M不変データ") else {
        panic!("下位型である法則はマーカーを持つ設計概念についての全称でなければならない");
    };
    assert_eq!(
        走る範囲,
        対象集合::マーカーを持つ設計概念 {
            マーカー名: "M状態".to_string(),
            名乗り方: マーカーの名乗り方::実装した型,
        }
    );
    let 命題::原子(原子) = 本体.as_ref() else {
        panic!("下位型である法則の全称の本体は原子命題1つでなければならない");
    };
    assert!(
        matches!(
            原子,
            原子命題::設計関係の経路が在る {
                種類: 設計関係の種類::下位型である, ..
            }
        ),
        "下位型である法則が経路の原子で書かれていない: {}",
        原子.表記()
    );
}

#[test]
fn 二段の経路しか無いグラフでも下位型である法則は証明済みになる() {
    let グラフ = 実装と上位トレイトが繋がったグラフ();
    let 結末 = 構造の検証器::生成する(&グラフ).検証する(&下位型である法則を組む("M状態", "M不変データ"));
    assert!(結末.証明済みか(), "2辺の経路しか無いグラフで下位型である法則が証明済みにならなかった: {}", 結末.表記());
}

#[test]
fn 設計関係へ参加する法則は参加していない原子の否定で問う() {
    let 命題::全称 { 対象集合: 走る範囲, 本体, .. } = 設計関係へ参加する法則を組む("Mエンティティ") else {
        panic!("設計関係へ参加する法則はマーカーを持つ設計概念についての全称でなければならない");
    };
    assert_eq!(
        走る範囲,
        対象集合::マーカーを持つ設計概念 {
            マーカー名: "Mエンティティ".to_string(),
            名乗り方: マーカーの名乗り方::実装した型,
        }
    );
    let 命題::否定(内側) = 本体.as_ref() else {
        panic!("設計関係へ参加する法則の全称の本体は否定でなければならない");
    };
    assert!(
        matches!(内側.as_ref(), 命題::原子(原子命題::設計関係へ1つも参加していない { .. })),
        "否定の内側が設計関係へ1つも参加していないの原子でない: {}",
        内側.表記()
    );
}
