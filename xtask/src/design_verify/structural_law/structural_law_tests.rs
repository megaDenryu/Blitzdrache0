//! 入口の法則が、どの原子命題で書かれているかを命題の木から確かめ、分類を参加に数えないことを小さなグラフで確かめる試験。
//!
//! **命題の `表記()` の文字列を照合しない。** 表記は人が読むための文であり、文言を変えただけで落ちる試験は
//! 守りたいもの(どの原子で問うか)と違う理由で落ちる。原子の選択肢を分解して見る。

use std::path::PathBuf;

use blitz_design_verification::{マーカーの実装の事実, 事実の出どころ, 分類の事実, 原子命題, 命題, 命題の検証器, 対象集合, 構造の検証器, 関係を落とした抽出の欠落};

use crate::design_model::{
    抽出の出どころ, 抽出元の構文, 設計概念, 設計概念への参照, 設計解釈マーカーの参照, 設計解釈マーカーの正本のモジュールパス, 設計関係, 設計関係の種類, 設計関係グラフ
};

use super::{構造の法則の命題の集合を組む, 設計関係へ参加する法則を組む};

const 型のモジュール: &str = "blitz_esca::traveler";

/// `旅行者` が `Mエンティティ` を実装し、識別するの辺を持つかどうかだけが違うグラフ。
fn エンティティを1件持つグラフ(識別するの辺を持つか: bool) -> 設計関係グラフ {
    let 旅行者 = 設計概念への参照::型として生成する(型のモジュール, "旅行者");
    let 旅行者の識別子 = 設計概念への参照::型として生成する(型のモジュール, "旅行者ID");
    let 実装 = マーカーの実装の事実 {
        型: 旅行者.clone(),
        マーカー: 設計解釈マーカーの参照("Mエンティティ"),
        出どころ: 事実の出どころ {
            パス: PathBuf::from("crates/blitz_esca/src/traveler.rs"),
            行番号: 1,
        },
    };
    let 識別する辺 = 設計関係 {
        主語: 旅行者の識別子,
        種類: 設計関係の種類::識別する,
        目的語: 旅行者,
        出どころ: 抽出の出どころ {
            パス: PathBuf::from("crates/blitz_esca/src/traveler.rs"),
            行番号: 2,
            構文: 抽出元の構文::エンティティの識別子の関連型,
        },
    };
    let 概念一覧 = vec![
        設計概念::型として生成する(型のモジュール, "旅行者"),
        設計概念::型として生成する(型のモジュール, "旅行者ID"),
        設計概念::トレイトとして生成する(&設計解釈マーカーの正本のモジュールパス(), "Mエンティティ"),
    ];
    let 関係一覧 = if 識別するの辺を持つか { vec![識別する辺] } else { Vec::new() };
    設計関係グラフ::生成する(概念一覧, 関係一覧, 分類の事実::生成する(vec![実装], Vec::new())).グラフ
}

#[test]
fn 設計関係へ参加する法則は参加していない原子の否定で問う() {
    let 命題::全称 { 対象集合: 走る範囲, 本体, .. } = 設計関係へ参加する法則を組む("Mエンティティ") else {
        panic!("設計関係へ参加する法則はマーカーを持つ設計概念についての全称でなければならない");
    };
    assert_eq!(
        走る範囲,
        対象集合::マーカーを持つ設計概念 {
            マーカー名: "Mエンティティ".to_string()
        }
    );
    let 命題::否定(内側) = 本体.as_ref() else {
        panic!("設計関係へ参加する法則の全称の本体は否定でなければならない");
    };
    assert!(
        matches!(内側.as_ref(), 命題::原子(原子命題::設計関係へ1つも参加していない { .. })),
        "否定の内側が設計関係へ1つも参加していないの原子でない: {}",
        内側.表記()
    );
}

#[test]
fn マーカーを実装しただけで辺を持たない型は参加の法則の反例になる() {
    let グラフ = エンティティを1件持つグラフ(false);
    let 結果 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&設計関係へ参加する法則を組む("Mエンティティ"));
    assert!(結果.反証済みか(), "分類のラベルを参加に数えている: {}", 結果.表記());
}

#[test]
fn 識別するの辺を持つエンティティは参加の法則を満たす() {
    let グラフ = エンティティを1件持つグラフ(true);
    let 結果 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(&設計関係へ参加する法則を組む("Mエンティティ"));
    assert!(結果.証明済みか(), "{}", 結果.表記());
}

#[test]
fn 法則の集合は参加の法則の1件だけを持つ() {
    let 名前一覧: Vec<&str> = 構造の法則の命題の集合を組む().命題一覧().iter().map(|命題| 命題.名前()).collect();
    assert_eq!(名前一覧, vec!["Mエンティティを名乗る型は設計関係へ1つ以上参加している"]);
}
