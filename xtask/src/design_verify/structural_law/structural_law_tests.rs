//! 存在理由の公理の5つが、それぞれ成立するグラフで証明済みになり、反例を持つグラフで反証済みになることを小さなグラフで固定する試験。
//!
//! 1つのグラフ(`存在理由の公理の試験のグラフ`)は、公理のマーカーを名乗る対象の型1つと、処理1つと、容器の型1つだけを持つ。対象の型がどう使われるかだけを変え、
//! 直に使われるとき・容器に持たれるときに成立し、どちらでもないときに反例になることを見る。

use blitz_design_verification::{名前付きの命題, 命題の検証器, 構造の検証器, 関係を落とした抽出の欠落};

use crate::design_model::設計関係の種類;

use super::存在理由の公理の試験のグラフ::{グラフ, 使われ方};
use super::構造の法則の命題の集合を組む;

// 名前が公理の名乗るマーカーで始まる公理を集合から採る。
fn 公理(マーカー名: &str) -> 名前付きの命題 {
    let 集合 = 構造の法則の命題の集合を組む();
    let Some(公理) = 集合.命題一覧().iter().find(|命題| 命題.名前().starts_with(&format!("{マーカー名}を名乗る型は"))) else {
        panic!("{マーカー名}の存在理由の公理が集合に無い");
    };
    公理.clone()
}

fn 証明済みか(マーカー名: &'static str, 使われ方: 使われ方) -> bool {
    let グラフ = グラフ(マーカー名, 使われ方);
    let 結果 = 構造の検証器::生成する(&グラフ, 関係を落とした抽出の欠落::無い()).検証する(公理(マーカー名).命題());
    assert!(結果.証明済みか() || 結果.反証済みか(), "未決定で答えた: {}", 結果.表記());
    結果.証明済みか()
}

#[test]
fn 法則の集合は5つのマーカーの存在理由の公理を持つ() {
    let 集合 = 構造の法則の命題の集合を組む();
    assert_eq!(集合.命題一覧().len(), 5);
    for マーカー名 in ["Mコマンド", "M規則", "M状態", "M解釈前の入力", "Mイベント"] {
        公理(マーカー名);
    }
}

#[test]
fn どの公理も処理が直に関係を張る型で成立し処理に使われない型で反証される() {
    for (マーカー名, 種類) in [
        ("Mコマンド", 設計関係の種類::消費する),
        ("M規則", 設計関係の種類::参照する),
        ("M状態", 設計関係の種類::消費する),
        ("M解釈前の入力", 設計関係の種類::消費する),
        ("Mイベント", 設計関係の種類::生成する),
    ] {
        assert!(証明済みか(マーカー名, 使われ方::処理が直に関係を張る(種類)), "{マーカー名}: 直に使われる型で成立しない");
        assert!(!証明済みか(マーカー名, 使われ方::使われない), "{マーカー名}: 処理に使われない型が反例にならない");
    }
}

#[test]
fn 処理の関係の種類が違えば直に使われたことにならない() {
    assert!(!証明済みか("Mコマンド", 使われ方::処理が直に関係を張る(設計関係の種類::生成する)), "生成されるだけのコマンドを消費されたと数えた");
    assert!(!証明済みか("M規則", 使われ方::処理が直に関係を張る(設計関係の種類::消費する)), "消費されるだけの規則を参照されたと数えた");
    assert!(!証明済みか("Mイベント", 使われ方::処理が直に関係を張る(設計関係の種類::消費する)), "消費されるだけのイベントを生成されたと数えた");
}

#[test]
fn 処理に使われる容器に保持される型は成立する() {
    for (マーカー名, 容器のマーカー名, 容器への関係) in [
        ("Mコマンド", "MParameter", 設計関係の種類::消費する),
        ("M規則", "M規則", 設計関係の種類::参照する),
        ("M規則", "MParameter", 設計関係の種類::消費する),
        ("M状態", "M状態", 設計関係の種類::消費する),
        ("M状態", "MParameter", 設計関係の種類::消費する),
        ("M解釈前の入力", "M解釈前の入力", 設計関係の種類::消費する),
        ("M解釈前の入力", "MParameter", 設計関係の種類::消費する),
    ] {
        let 使われ方 = 使われ方::容器に持たれる { 容器のマーカー名, 容器への関係 };
        assert!(証明済みか(マーカー名, 使われ方), "{マーカー名}: 処理に使われる{容器のマーカー名}に保持される型で成立しない");
    }
}

#[test]
fn 容器と数えないマーカーの型に保持されるだけの型は反証される() {
    let コマンドを状態が持つ = 使われ方::容器に持たれる {
        容器のマーカー名: "M状態",
        容器への関係: 設計関係の種類::消費する,
    };
    assert!(!証明済みか("Mコマンド", コマンドを状態が持つ), "状態に保持されるだけのコマンドを消費されたと数えた");
    let イベントを引数が持つ = 使われ方::容器に持たれる {
        容器のマーカー名: "MParameter",
        容器への関係: 設計関係の種類::消費する,
    };
    assert!(!証明済みか("Mイベント", イベントを引数が持つ), "引数に保持されるだけのイベントを生成されたと数えた");
}
