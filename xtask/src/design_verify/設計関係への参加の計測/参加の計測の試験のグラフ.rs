//! 設計関係への参加の計測の試験が使う、節点の種類を1つずつ揃えたグラフと、その辺を組む道具。
//!
//! グラフは次の節点を持つ。辺も分類も持たない `blitz_esca` の型、マーカーの実装の事実だけを持つ `blitz_game` の型、
//! マーカーの実装の事実と保持の辺を持つ `blitz_esca` の型、ドメインのクレートの外の `blitz_sim` の型、
//! 設計解釈マーカーのトレイト2つ(分類の事実に現れるものと現れないもの)、`blitz_esca` に在る処理の節点1つ、
//! `blitz_esca::ontology` に在る関数の役割の型 `M遷移関数` と意味型 `遷移成功結果`、定義をたどれずモジュールパスが空の型1つである。

use std::path::PathBuf;

use blitz_design_verification::{マーカーの実装の事実, 事実の出どころ, 分類の事実};

use crate::design_model::{抽出の出どころ, 抽出元の構文, 設計概念, 設計概念への参照, 設計解釈マーカーの正本のモジュールパス, 設計関係, 設計関係の種類, 設計関係グラフ};

// 遷移関数の役割と意味型を定義するモジュールのパス。`role` の宣言と独立に書き、宣言がずれたら試験が落ちるようにする。
const 遷移関数の役割のモジュール: &str = "blitz_esca::ontology";

fn 辺(主語: &設計概念への参照, 種類: 設計関係の種類, 目的語: &設計概念への参照, 構文: 抽出元の構文) -> 設計関係 {
    設計関係 {
        主語: 主語.clone(),
        種類,
        目的語: 目的語.clone(),
        出どころ: 抽出の出どころ {
            パス: PathBuf::from("crates/blitz_esca/src/試験の辺の出どころ.rs"),
            行番号: 1,
            構文,
        },
    }
}

fn マーカーの実装(型: &設計概念への参照, マーカー: &設計概念への参照) -> マーカーの実装の事実 {
    マーカーの実装の事実 {
        型: 型.clone(),
        マーカー: マーカー.clone(),
        出どころ: 事実の出どころ {
            パス: PathBuf::from("crates/blitz_esca/src/試験の辺の出どころ.rs"),
            行番号: 1,
        },
    }
}

pub fn 試験のグラフ() -> 設計関係グラフ {
    let マーカーの正本 = 設計解釈マーカーの正本のモジュールパス();
    let 孤立した型 = 設計概念::型として生成する("blitz_esca::walking_direction", "歩行方向");
    let マーカーだけの型 = 設計概念::型として生成する("blitz_game::game_phase", "ゲームの進行段階");
    let 保持する型 = 設計概念::型として生成する("blitz_esca::traveler", "旅行者");
    let 範囲の外の型 = 設計概念::型として生成する("blitz_sim::rigid_body", "剛体");
    let 事実に現れるマーカー = 設計概念::トレイトとして生成する(&マーカーの正本, "M状態");
    let 事実に現れないマーカー = 設計概念::トレイトとして生成する(&マーカーの正本, "M観測");
    let 処理 = 設計概念::処理として生成する("blitz_esca::traveler_movement", "旅行者を歩かせる");
    let 役割の型 = 設計概念::型として生成する(遷移関数の役割のモジュール, "M遷移関数");
    let 意味型 = 設計概念::型として生成する(遷移関数の役割のモジュール, "遷移成功結果");
    let 定義をたどれなかった型 = 設計概念::型として生成する("", "移動状態");
    let [マーカーだけ, 保持, マーカー] = [&マーカーだけの型, &保持する型, &事実に現れるマーカー].map(設計概念::参照を組む);
    let 関係一覧 = vec![辺(&保持, 設計関係の種類::保持する, &範囲の外の型.参照を組む(), 抽出元の構文::構造体のフィールド)];
    let 事実 = 分類の事実::生成する(vec![マーカーの実装(&マーカーだけ, &マーカー), マーカーの実装(&保持, &マーカー)], Vec::new());
    let 概念一覧 = vec![孤立した型, マーカーだけの型, 保持する型, 範囲の外の型, 事実に現れるマーカー, 事実に現れないマーカー, 処理, 役割の型, 意味型, 定義をたどれなかった型];
    設計関係グラフ::生成する(概念一覧, 関係一覧, 事実).グラフ
}
