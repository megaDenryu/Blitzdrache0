//! 設計関係への参加の計測の試験が使う、節点の種類を1つずつ揃えたグラフと、その辺を組む道具。
//!
//! グラフは次の節点を持つ。辺も分類も持たない `blitz_esca` の型、マーカーの実装の事実だけを持つ `blitz_game` の型、
//! マーカーの実装の事実と保持する関係の辺を持つが設計関係の辺を持たない `blitz_esca` の型、処理に消費される(設計関係の辺を持つ) `blitz_esca` の型、
//! 保持する関係の目的語にだけ現れるドメインのクレートの外の `blitz_sim` の型、設計解釈マーカーのトレイト2つ(分類の事実に現れるものと現れないもの)、
//! `blitz_esca` に在る処理の節点1つ、`blitz_esca::ontology` に在る関数の役割の型 `M遷移関数` と意味型 `遷移成功結果`、定義をたどれずモジュールパスが空の型1つである。

use std::path::PathBuf;

use blitz_design_verification::{マーカーの実装の事実, 事実の出どころ, 保持する関係, 分類の事実, 導出の根拠, 設計関係, 設計関係の種類};

use crate::design_model::{抽出の出どころ, 抽出元の構文, 設計概念, 設計概念への参照, 設計解釈マーカーの正本のモジュールパス, 設計関係グラフ};

// 遷移関数の役割と意味型を定義するモジュールのパス。`role` の宣言と独立に書き、宣言がずれたら試験が落ちるようにする。
const 遷移関数の役割のモジュール: &str = "blitz_esca::ontology";

fn 辺の出どころ(構文: 抽出元の構文) -> 抽出の出どころ {
    抽出の出どころ {
        パス: PathBuf::from("crates/blitz_esca/src/試験の辺の出どころ.rs"),
        行番号: 1,
        構文,
    }
}

fn 保持する辺(主語: &設計概念への参照, 目的語: &設計概念への参照) -> 保持する関係 {
    保持する関係 {
        主語: 主語.clone(),
        目的語: 目的語.clone(),
        出どころ: 辺の出どころ(抽出元の構文::構造体のフィールド),
        根拠: 導出の根拠::生成する("試験が定義の式を通さずに直に置いた関係", Vec::new()),
    }
}

fn 消費する辺(処理: &設計概念への参照, 目的語: &設計概念への参照) -> 設計関係 {
    設計関係 {
        主語: 処理.clone(),
        種類: 設計関係の種類::消費する,
        目的語: 目的語.clone(),
        出どころ: 辺の出どころ(抽出元の構文::関数の役割の型引数),
        根拠: 導出の根拠::生成する("試験が定義の式を通さずに直に置いた関係", Vec::new()),
    }
}

fn マーカーの実装(型: &設計概念への参照, マーカー: &設計概念への参照) -> マーカーの実装の事実 {
    マーカーの実装の事実 {
        型: 型.clone(),
        マーカー: マーカー.clone(),
        出どころ: 事実の出どころ {
            パス: PathBuf::from("crates/blitz_esca/src/試験の辺の出どころ.rs"),
            行番号: 1,
        },
    }
}

pub fn 試験のグラフ() -> 設計関係グラフ {
    let マーカーの正本 = 設計解釈マーカーの正本のモジュールパス();
    let 孤立した型 = 設計概念::型として生成する("blitz_esca::walking_direction", "歩行方向");
    let マーカーだけの型 = 設計概念::型として生成する("blitz_game::game_phase", "ゲームの進行段階");
    let 保持するだけの型 = 設計概念::型として生成する("blitz_esca::traveler", "旅行者の現在地");
    let 消費される型 = 設計概念::型として生成する("blitz_esca::traveler", "旅行者");
    let 範囲の外の型 = 設計概念::型として生成する("blitz_sim::rigid_body", "剛体");
    let 事実に現れるマーカー = 設計概念::トレイトとして生成する(&マーカーの正本, "M状態");
    let 事実に現れないマーカー = 設計概念::トレイトとして生成する(&マーカーの正本, "M観測");
    let 処理 = 設計概念::処理として生成する("blitz_esca::traveler_movement", "旅行者を歩かせる");
    let 役割の型 = 設計概念::型として生成する(遷移関数の役割のモジュール, "M遷移関数");
    let 意味型 = 設計概念::型として生成する(遷移関数の役割のモジュール, "遷移成功結果");
    let 定義をたどれなかった型 = 設計概念::型として生成する("", "移動状態");
    let [マーカーだけ, 保持するだけ, 消費される, マーカー] = [&マーカーだけの型, &保持するだけの型, &消費される型, &事実に現れるマーカー].map(設計概念::参照を組む);
    let 設計関係一覧 = vec![消費する辺(&処理.参照を組む(), &消費される)];
    let 保持する関係一覧 = vec![保持する辺(&保持するだけ, &範囲の外の型.参照を組む())];
    let 事実 = 分類の事実::生成する(
        vec![マーカー.clone(), 事実に現れないマーカー.参照を組む()],
        vec![マーカーの実装(&マーカーだけ, &マーカー), マーカーの実装(&保持するだけ, &マーカー)],
        Vec::new(),
    );
    let 概念一覧 = vec![
        孤立した型,
        マーカーだけの型,
        保持するだけの型,
        消費される型,
        範囲の外の型,
        事実に現れるマーカー,
        事実に現れないマーカー,
        処理,
        役割の型,
        意味型,
        定義をたどれなかった型,
    ];
    設計関係グラフ::生成する(概念一覧, 設計関係一覧, 保持する関係一覧, 事実).グラフ
}
