//! 母集団の選び方とは、母集団の案が設計関係グラフのどの節点を母集団に採るかの別のことである。
//! このファイルは、選び方と、選び方が母集団を採ったときに何を外し何を含めたかの内訳を持つ。
//!
//! ドメインのクレートから採る選び方は、関数の役割の型(`M遷移関数` 等)と、役割に伴う意味型(`遷移成功結果`・`遷移失敗結果`)を外す。
//! この2つはドメインのクレートに定義が在っても、処理の役割の層に置かれた設計語彙であり、ドメイン概念ではないためである
//! (`_doc/設計/設計オントロジー.md` 2.1節・第3節)。外した節点は黙って消さず、内訳へ残して表示する。
//! 定義をたどれずモジュールパスが空の節点はクレート名を持たないため、ドメインのクレートから採る選び方の母集団には入らない。
//! グラフの全ての節点を採る選び方はこの節点を含め、検証器がこの節点について未決定を答えるため、内訳へその件数を残す。

use crate::design_model::{ドメインのクレートか, ドメインのクレートの名前一覧, 設計概念, 設計概念の種類, 設計概念への参照, 設計関係グラフ, 関数の役割の型か意味型を指す参照か};

/// 母集団をグラフのどの節点から採るか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 母集団の選び方 {
    ドメインのクレートの型から関数の役割の型と意味型を除いたもの, // 種類が型であり、定義のモジュールパスがドメインのクレートに在る節点
    グラフの全ての節点,                                           // 種類もクレートも問わない
}

/// 選び方が母集団を採ったときの内訳。どの選び方で採ったかによって、表示すべき事実が違う。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 母集団を採った内訳 {
    ドメインのクレートから採った { 外した関数の役割の型と意味型: Vec<設計概念への参照> },
    全ての節点を採った { モジュールパスが空の節点の件数: usize },
}

impl 母集団の選び方 {
    /// 見出しに書く選び方の1句。ドメインのクレートの名前は設計オントロジーの適用範囲から導く。
    pub fn 説明(self) -> String {
        match self {
            Self::ドメインのクレートの型から関数の役割の型と意味型を除いたもの => {
                format!("ドメインのクレート {} の型から、関数の役割の型と意味型を除いたもの", ドメインのクレートの名前一覧().collect::<Vec<_>>().join("・"))
            }
            Self::グラフの全ての節点 => "設計関係グラフの全ての節点".to_string(),
        }
    }

    /// グラフから母集団を採り、採った内訳を添えて返す。
    pub fn 母集団を採る(self, グラフ: &設計関係グラフ) -> (Vec<&設計概念>, 母集団を採った内訳) {
        match self {
            Self::ドメインのクレートの型から関数の役割の型と意味型を除いたもの => {
                let ドメインのクレートの型 = グラフ.概念一覧().iter().filter(|概念| 概念.種類() == 設計概念の種類::型 && ドメインのクレートか(概念.識別子().クレート名()));
                let (外した, 母集団): (Vec<&設計概念>, Vec<&設計概念>) = ドメインのクレートの型.partition(|概念| 関数の役割の型か意味型を指す参照か(&概念.参照を組む()));
                let 外した関数の役割の型と意味型 = 外した.iter().map(|概念| 概念.参照を組む()).collect();
                (母集団, 母集団を採った内訳::ドメインのクレートから採った { 外した関数の役割の型と意味型 })
            }
            Self::グラフの全ての節点 => {
                let 母集団: Vec<&設計概念> = グラフ.概念一覧().iter().collect();
                let モジュールパスが空の節点の件数 = 母集団.iter().filter(|概念| 概念.識別子().Rustの項目でありながら定義をたどれていないか()).count();
                (母集団, 母集団を採った内訳::全ての節点を採った { モジュールパスが空の節点の件数 })
            }
        }
    }
}
