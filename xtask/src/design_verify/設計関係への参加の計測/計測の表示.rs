//! 設計関係への参加の計測の表示。`Display` の実装と、その実装が使う理由の1文だけを持つ(トレイト実装の分離)。
//!
//! 欠落の件数を案ごとの数の前に出すのは、読み手が案の数を読む前に「この数は本番の命題の答えではない」ことを知るためである。
//! 例を上限の件数で切るが、件数は全件を出す。検査器が数えた件数を必ず報告する規約に従うためである
//! (`.claude/global-reference/全プロジェクト共通CLAUDE.md`「検査器は解析できなかった入力を黙って対象から外してはならない」)。

use std::fmt;

use super::super::extraction_report::種類の呼び名;
use super::{参加していない理由, 案ごとの計測, 設計関係への参加の計測};

// 参加していない概念の例を案ごとに表示する上限。
const 例を表示する上限: usize = 5;

impl fmt::Display for 設計関係への参加の計測 {
    fn fmt(&self, 書き先: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(書き先, "  この計測は命題へ接続していない。合否と終了コードに効かない")?;
        writeln!(書き先, "  数は、検証器が抽出の欠落によって答えを弱める前の数であり、設計関係グラフへ直接尋ねて数えた")?;
        writeln!(書き先, "  抽出の欠落: {}。抽出できなかった行のうち保証範囲の外の構文は{}件である", self.欠落.説明(), self.保証範囲の外の構文の件数)?;
        if self.欠落.在るか() {
            writeln!(
                書き先,
                "  欠落が{}件在るため、母集団の全ての概念が設計関係へ参加するという全称の命題を接続しても、検証器は参加していない概念を反例として答えず、未決定を答える",
                self.欠落.合計の件数()
            )?;
        } else {
            writeln!(書き先, "  欠落が0件であるため、全称の命題を接続すれば、検証器は参加していない概念を反例として答える")?;
        }
        for 計測 in &self.案ごとの計測一覧 {
            write!(書き先, "{計測}")?;
        }
        Ok(())
    }
}

impl fmt::Display for 案ごとの計測 {
    fn fmt(&self, 書き先: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(書き先, "  {}: 母集団{}件のうち、設計関係へ参加していない概念は{}件である", self.案.呼び名(), self.母集団の件数, self.参加していない概念一覧.len())?;
        for 概念 in self.参加していない概念一覧.iter().take(例を表示する上限) {
            writeln!(書き先, "    例: {}({}): {}", 概念.参照.表記(), 種類の呼び名(概念.参照.種類()), 概念.理由.説明())?;
        }
        Ok(())
    }
}

impl 参加していない理由 {
    // 人が読む理由の1文。
    fn 説明(self) -> String {
        match self {
            Self::辺が1本も無い => "主語としても目的語としても辺が1本も無い".to_string(),
            Self::マーカーへの下位型であるの辺しか無い { 本数 } => format!("触れる辺{本数}本がどれも設計解釈マーカーへの下位型であるの辺である"),
        }
    }
}
