//! 設計関係への参加の計測が、母集団の選び方と参加の数え方を案ごとに正しく当てることを固定する試験。
//!
//! 試験のグラフは4種類の節点を持つ。辺を持たない `blitz_esca` の型、マーカーの実装の辺だけを持つ `blitz_game` の型、
//! マーカーの実装の辺と保持の辺を持つ `blitz_esca` の型、ドメインのクレートの外の `blitz_sim` の型である。
//! これに設計解釈マーカーのトレイト2つ(辺が在るものと無いもの)と、`blitz_esca` に在る処理の節点1つを加える。
//! 同じグラフを3つの案で数え、案ごとに母集団と参加していない概念の並びが変わることを見る。

use std::path::PathBuf;

use blitz_design_verification::関係を落とした抽出の欠落;

use crate::design_model::{抽出の出どころ, 抽出した設計関係グラフと抽出の欠け, 抽出元の構文, 設計概念, 設計概念への参照, 設計関係, 設計関係の種類, 設計関係グラフ};

use super::{参加していない概念, 参加していない理由, 母集団の案, 設計関係への参加の計測};

const マーカーの正本: &str = "blitz_design::marker";

fn 辺(主語: &設計概念への参照, 種類: 設計関係の種類, 目的語: &設計概念への参照, 構文: 抽出元の構文) -> 設計関係 {
    設計関係 {
        主語: 主語.clone(),
        種類,
        目的語: 目的語.clone(),
        出どころ: 抽出の出どころ {
            パス: PathBuf::from("crates/blitz_esca/src/試験の辺の出どころ.rs"),
            行番号: 1,
            構文,
        },
    }
}

fn 試験のグラフ() -> 設計関係グラフ {
    let 孤立した型 = 設計概念::型として生成する("blitz_esca::walking_direction", "歩行方向");
    let マーカーだけの型 = 設計概念::型として生成する("blitz_game::game_phase", "ゲームの進行段階");
    let 保持する型 = 設計概念::型として生成する("blitz_esca::traveler", "旅行者");
    let 範囲の外の型 = 設計概念::型として生成する("blitz_sim::rigid_body", "剛体");
    let 辺の在るマーカー = 設計概念::トレイトとして生成する(マーカーの正本, "M状態");
    let 辺の無いマーカー = 設計概念::トレイトとして生成する(マーカーの正本, "M観測");
    let 処理 = 設計概念::処理として生成する("blitz_esca::traveler_movement", "旅行者を歩かせる");
    let [マーカーだけ, 保持, マーカー] = [&マーカーだけの型, &保持する型, &辺の在るマーカー].map(設計概念::参照を組む);
    let 関係一覧 = vec![
        辺(&マーカーだけ, 設計関係の種類::下位型である, &マーカー, 抽出元の構文::設計解釈マーカーの実装),
        辺(&保持, 設計関係の種類::下位型である, &マーカー, 抽出元の構文::設計解釈マーカーの実装),
        辺(&保持, 設計関係の種類::保持する, &範囲の外の型.参照を組む(), 抽出元の構文::構造体のフィールド),
    ];
    設計関係グラフ::生成する(vec![孤立した型, マーカーだけの型, 保持する型, 範囲の外の型, 辺の在るマーカー, 辺の無いマーカー, 処理], 関係一覧).グラフ
}

// 参加していない概念の一覧を、表記と理由の組へ写す。期待値を表記の文字列で書けるようにするためである。
fn 表記と理由の一覧(一覧: &[参加していない概念]) -> Vec<(String, 参加していない理由)> {
    一覧.iter().map(|概念| (概念.参照.表記(), 概念.理由)).collect()
}

fn 期待(一覧: &[(&str, 参加していない理由)]) -> Vec<(String, 参加していない理由)> {
    一覧.iter().map(|(表記, 理由)| ((*表記).to_string(), *理由)).collect()
}

#[test]
fn 案1はドメインのクレートの型だけを母集団にしマーカーの実装の辺を参加に数える() {
    let [案1, _, _] = 母集団の案::裁定を待つ3つの案();
    let 計測 = 案1.グラフで数える(&試験のグラフ());
    assert_eq!(計測.母集団の件数, 3, "blitz_sim の型とトレイトと処理の節点は案1の母集団に入らない");
    assert_eq!(表記と理由の一覧(&計測.参加していない概念一覧), 期待(&[("blitz_esca::walking_direction::歩行方向", 参加していない理由::辺が1本も無い)]));
}

#[test]
fn 案2はマーカーへの下位型であるの辺しか持たない型を参加していないと数える() {
    let [_, 案2, _] = 母集団の案::裁定を待つ3つの案();
    let 計測 = 案2.グラフで数える(&試験のグラフ());
    assert_eq!(計測.母集団の件数, 3);
    assert_eq!(
        表記と理由の一覧(&計測.参加していない概念一覧),
        期待(&[
            ("blitz_esca::walking_direction::歩行方向", 参加していない理由::辺が1本も無い),
            ("blitz_game::game_phase::ゲームの進行段階", 参加していない理由::マーカーへの下位型であるの辺しか無い { 本数: 1 }),
        ]),
        "旅行者は保持の辺を持つため、マーカーの実装の辺を除いても参加している"
    );
}

#[test]
fn 案3はグラフの全ての節点を母集団にし目的語として触れる辺も参加に数える() {
    let [_, _, 案3] = 母集団の案::裁定を待つ3つの案();
    let 計測 = 案3.グラフで数える(&試験のグラフ());
    assert_eq!(計測.母集団の件数, 7);
    assert_eq!(
        表記と理由の一覧(&計測.参加していない概念一覧),
        期待(&[
            ("blitz_esca::walking_direction::歩行方向", 参加していない理由::辺が1本も無い),
            ("blitz_design::marker::M観測", 参加していない理由::辺が1本も無い),
            ("blitz_esca::traveler_movement::旅行者を歩かせる", 参加していない理由::辺が1本も無い),
        ]),
        "M状態と剛体は目的語としてだけ辺に触れるが、参加に数える"
    );
}

#[test]
fn 名前がマーカーと同じでもマーカーの正本に無いトレイトへの辺は案2でも参加に数える() {
    let 偽のマーカー = 設計概念::トレイトとして生成する("blitz_game::game_phase", "M状態");
    let 型 = 設計概念::型として生成する("blitz_game::game_phase", "ゲームの進行段階");
    let 関係 = 辺(&型.参照を組む(), 設計関係の種類::下位型である, &偽のマーカー.参照を組む(), 抽出元の構文::設計解釈マーカーの実装);
    let グラフ = 設計関係グラフ::生成する(vec![偽のマーカー, 型], vec![関係]).グラフ;
    let [_, 案2, _] = 母集団の案::裁定を待つ3つの案();
    assert!(案2.グラフで数える(&グラフ).参加していない概念一覧.is_empty());
}

#[test]
fn 計測は3つの案をこの順に並べ受け取った欠落を運ぶ() {
    let 抽出したもの = 抽出した設計関係グラフと抽出の欠け {
        グラフ: 試験のグラフ(),
        ..抽出した設計関係グラフと抽出の欠け::default()
    };
    let 計測 = 設計関係への参加の計測::計測する(&抽出したもの, &関係を落とした抽出の欠落::無い());
    assert_eq!(計測.案ごとの計測一覧.iter().map(|案| 案.参加していない概念一覧.len()).collect::<Vec<_>>(), vec![1, 2, 3]);
    assert!(!計測.欠落.在るか());
}
