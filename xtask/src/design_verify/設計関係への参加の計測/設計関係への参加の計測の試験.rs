//! 設計関係への参加の計測が、母集団の選び方と参加の数え方を案ごとに正しく当てることを固定する試験。
//!
//! 節点の種類を1つずつ揃えたグラフ(`参加の計測の試験のグラフ`)を3つの案で数え、案ごとに母集団と参加していない概念の並びと
//! 採った内訳が変わることを見る。

use blitz_design_verification::関係を落とした抽出の欠落;

use crate::design_model::{ドメインのクレートの名前一覧, 抽出した設計関係グラフと抽出の欠け, 抽出元の構文, 設計概念, 設計概念への参照, 設計関係の種類, 設計関係グラフ};

use super::参加の計測の試験のグラフ::{試験のグラフ, 辺};
use super::{参加していない概念, 参加していない理由, 母集団の案, 母集団を採った内訳, 設計関係への参加の計測};

// 参加していない概念の一覧を、表記と理由の組へ写す。期待値を表記の文字列で書けるようにするためである。
fn 表記と理由の一覧(一覧: &[参加していない概念]) -> Vec<(String, 参加していない理由)> {
    一覧.iter().map(|概念| (概念.参照.表記(), 概念.理由)).collect()
}

fn 期待(一覧: &[(&str, 参加していない理由)]) -> Vec<(String, 参加していない理由)> {
    一覧.iter().map(|(表記, 理由)| ((*表記).to_string(), *理由)).collect()
}

// ドメインのクレートから採った内訳が外した節点の表記を、並びに依らず比べられるよう整列して返す。
fn 外した節点の表記一覧(内訳: &母集団を採った内訳) -> Vec<String> {
    let 母集団を採った内訳::ドメインのクレートから採った { 外した関数の役割の型と意味型 } = 内訳 else {
        panic!("ドメインのクレートから採る案の内訳が別の選択肢になった: {内訳:?}");
    };
    let mut 表記一覧: Vec<String> = 外した関数の役割の型と意味型.iter().map(設計概念への参照::表記).collect();
    表記一覧.sort();
    表記一覧
}

#[test]
fn 案1はドメインのクレートの型から関数の役割の型と意味型を外しマーカーの実装の辺を参加に数える() {
    let [案1, _, _] = 母集団の案::裁定を待つ3つの案();
    let クレートの並び = ドメインのクレートの名前一覧().collect::<Vec<_>>().join("・");
    assert!(案1.見出し().contains(&クレートの並び), "見出しのクレートの名前は適用範囲から導く: {}", 案1.見出し());
    let 計測 = 案1.グラフで数える(&試験のグラフ());
    assert_eq!(計測.母集団の件数, 3, "blitz_sim の型・トレイト・処理・関数の役割の型・意味型・モジュールパスが空の型は案1の母集団に入らない");
    assert_eq!(外した節点の表記一覧(&計測.内訳), vec!["blitz_esca::ontology::M遷移関数".to_string(), "blitz_esca::ontology::遷移成功結果".to_string()]);
    assert_eq!(表記と理由の一覧(&計測.参加していない概念一覧), 期待(&[("blitz_esca::walking_direction::歩行方向", 参加していない理由::辺が1本も無い)]));
}

#[test]
fn 案2はマーカーへの下位型であるの辺しか持たない型を参加していないと数える() {
    let [_, 案2, _] = 母集団の案::裁定を待つ3つの案();
    let 計測 = 案2.グラフで数える(&試験のグラフ());
    assert_eq!(計測.母集団の件数, 3);
    assert_eq!(
        表記と理由の一覧(&計測.参加していない概念一覧),
        期待(&[
            ("blitz_esca::walking_direction::歩行方向", 参加していない理由::辺が1本も無い),
            ("blitz_game::game_phase::ゲームの進行段階", 参加していない理由::マーカーへの下位型であるの辺しか無い { 本数: 1 }),
        ]),
        "旅行者は保持の辺を持つため、マーカーの実装の辺を除いても参加している"
    );
}

#[test]
fn 案3はグラフの全ての節点を母集団にしモジュールパスが空の節点を数える() {
    let [_, _, 案3] = 母集団の案::裁定を待つ3つの案();
    let 計測 = 案3.グラフで数える(&試験のグラフ());
    assert_eq!(計測.母集団の件数, 10);
    assert_eq!(
        計測.内訳,
        母集団を採った内訳::全ての節点を採った {
            モジュールパスが空の節点の件数: 1
        }
    );
    assert_eq!(
        表記と理由の一覧(&計測.参加していない概念一覧),
        期待(&[
            ("blitz_esca::walking_direction::歩行方向", 参加していない理由::辺が1本も無い),
            ("blitz_design::marker::M観測", 参加していない理由::辺が1本も無い),
            ("blitz_esca::traveler_movement::旅行者を歩かせる", 参加していない理由::辺が1本も無い),
            ("blitz_esca::ontology::M遷移関数", 参加していない理由::辺が1本も無い),
            ("blitz_esca::ontology::遷移成功結果", 参加していない理由::辺が1本も無い),
            ("移動状態", 参加していない理由::辺が1本も無い),
        ]),
        "M状態と剛体は目的語としてだけ辺に触れるが、参加に数える"
    );
    assert_eq!(計測.参加していない概念のうちモジュールパスが空の節点の件数(), 1, "検証器が未決定を答える節点は移動状態の1件である");
}

#[test]
fn 名前が関数の役割の型や意味型と同じでも定義の場所が違うドメインの型は母集団から外さない() {
    let 同名の型 = 設計概念::型として生成する("blitz_game::game_phase", "遷移成功結果");
    let 同名の役割 = 設計概念::型として生成する("blitz_game::game_phase", "M遷移関数");
    let グラフ = 設計関係グラフ::生成する(vec![同名の型, 同名の役割], Vec::new()).グラフ;
    let [案1, _, _] = 母集団の案::裁定を待つ3つの案();
    let 計測 = 案1.グラフで数える(&グラフ);
    assert_eq!(計測.母集団の件数, 2);
    assert!(外した節点の表記一覧(&計測.内訳).is_empty());
}

#[test]
fn 名前がマーカーと同じでもマーカーの正本に無いトレイトへの辺は案2でも参加に数える() {
    let 偽のマーカー = 設計概念::トレイトとして生成する("blitz_game::game_phase", "M状態");
    let 型 = 設計概念::型として生成する("blitz_game::game_phase", "ゲームの進行段階");
    let 関係 = 辺(&型.参照を組む(), 設計関係の種類::下位型である, &偽のマーカー.参照を組む(), 抽出元の構文::設計解釈マーカーの実装);
    let グラフ = 設計関係グラフ::生成する(vec![偽のマーカー, 型], vec![関係]).グラフ;
    let [_, 案2, _] = 母集団の案::裁定を待つ3つの案();
    assert!(案2.グラフで数える(&グラフ).参加していない概念一覧.is_empty());
}

#[test]
fn 計測は3つの案をこの順に並べ受け取った欠落を運ぶ() {
    let 抽出したもの = 抽出した設計関係グラフと抽出の欠け {
        グラフ: 試験のグラフ(),
        ..抽出した設計関係グラフと抽出の欠け::default()
    };
    let 計測 = 設計関係への参加の計測::計測する(&抽出したもの, &関係を落とした抽出の欠落::無い());
    assert_eq!(計測.案ごとの計測一覧.iter().map(|案| 案.参加していない概念一覧.len()).collect::<Vec<_>>(), vec![1, 2, 6]);
    assert!(!計測.欠落.在るか());
}
