//! 母集団の案とは、「すべてのドメイン概念は設計関係へ参加する」という全称の命題について、母集団をどの概念から採るかの別のことである。
//! このファイルは、オーナーの裁定を待つ2つの案と、1つの案でグラフを数える工程を持つ。
//!
//! 参加は設計関係の辺だけで数える。分類(マーカーの実装を上位トレイトの宣言で閉じたもの)は辺でないため数えない。
//! 分類を参加に数えると、マーカーを実装した型を母集団にした命題が構造上かならず真になるためである。
//! 案1はドメインのクレートの型を、案2はグラフの全ての節点(`blitz_design` のトレイトと関数の役割の処理の節点も含む)を母集団にする。
//! 母集団をどの節点から採るかは `母集団の選び方` が持つ。

use crate::design_model::{設計概念への参照, 設計関係グラフ};

use super::母集団の選び方::母集団の選び方;
use super::{参加していない概念, 参加していない理由, 案ごとの計測};

/// 母集団の案1件。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 母集団の案 {
    番号: u8, // 表示の見出しの案の番号
    選び方: 母集団の選び方,
}

impl 母集団の案 {
    /// オーナーの裁定を待つ2つの案。表示はこの順に並べる。
    pub const fn 裁定を待つ2つの案() -> [Self; 2] {
        [
            Self {
                番号: 1,
                選び方: 母集団の選び方::ドメインのクレートの型から関数の役割の型と意味型を除いたもの,
            },
            Self {
                番号: 2,
                選び方: 母集団の選び方::グラフの全ての節点,
            },
        ]
    }

    /// 表示の見出し。案の番号と母集団の選び方を1文で言う。
    pub fn 見出し(self) -> String {
        format!("案{}({}。設計関係の辺だけを数え、分類は数えない)", self.番号, self.選び方.説明())
    }

    /// この案でグラフを数える。欠落による弱めは掛けず、グラフの辺だけを見る。
    pub fn グラフで数える(self, グラフ: &設計関係グラフ) -> 案ごとの計測 {
        let (母集団, 内訳) = self.選び方.母集団を採る(グラフ);
        let 参加していない概念一覧 = 母集団
            .iter()
            .filter_map(|概念| {
                let 参照 = 概念.参照を組む();
                参加していない理由::グラフに尋ねる(グラフ, &参照).map(|理由| 参加していない概念 { 参照, 理由 })
            })
            .collect();
        案ごとの計測 {
            案: self,
            母集団の件数: 母集団.len(),
            内訳,
            参加していない概念一覧,
        }
    }
}

impl 参加していない理由 {
    /// その概念が辺を1本も持たないなら理由を答え、辺を持つなら何も答えない。分類の事実に現れるかで理由を分ける。
    fn グラフに尋ねる(グラフ: &設計関係グラフ, 参照: &設計概念への参照) -> Option<Self> {
        if !グラフ.関係へ1つも参加していないか(参照) {
            return None;
        }
        Some(if グラフ.分類を貸す().事実に現れるか(参照) {
            Self::分類の事実にだけ現れる
        } else {
            Self::辺も分類の事実も無い
        })
    }
}
