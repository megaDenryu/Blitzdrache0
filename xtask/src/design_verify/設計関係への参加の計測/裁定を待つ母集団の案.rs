//! 母集団の案とは、「すべてのドメイン概念は設計関係へ参加する」という全称の命題について、母集団をどの概念から採り、
//! 参加をどの辺で数えるかの組のことである。このファイルは、オーナーの裁定を待つ3つの案と、1つの案でグラフを数える工程を持つ。
//!
//! 案1と案2の違いは参加の数え方だけである。`impl マーカー for 型` は `下位型である` の辺を生むため、この辺を参加に数えると、
//! マーカーを実装した型を母集団にした命題は構造上かならず真になる(`structural_law` の「Mエンティティを名乗る型は
//! 設計関係へ1つ以上参加している」がこの形である)。案2はこの辺を数えないときの数を出し、案1との差がこの辺だけで参加していた概念の数になる。
//! 案3はグラフの全ての節点を母集団にし、`blitz_design` のトレイトと関数の役割の処理の節点も含める。
//! 母集団をどの節点から採るかは `母集団の選び方` が持つ。

use crate::design_model::{設計概念への参照, 設計解釈マーカーを指す参照か, 設計関係, 設計関係の種類, 設計関係グラフ};

use super::母集団の選び方::母集団の選び方;
use super::{参加していない概念, 参加していない理由, 案ごとの計測};

/// 母集団の案1件。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 母集団の案 {
    番号: u8, // 表示の見出しの案の番号
    選び方: 母集団の選び方,
    数え方: 参加の数え方,
}

/// 参加をどの辺で数えるか。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum 参加の数え方 {
    全ての辺を数える,                       // 検証器の `関係へ1つも参加していないか` と同じ数え方
    マーカーへの下位型であるの辺を数えない, // 設計解釈マーカーを目的語に取る `下位型である` の辺を除いて数える
}

impl 母集団の案 {
    /// オーナーの裁定を待つ3つの案。表示はこの順に並べる。
    pub const fn 裁定を待つ3つの案() -> [Self; 3] {
        [
            Self {
                番号: 1,
                選び方: 母集団の選び方::ドメインのクレートの型から関数の役割の型と意味型を除いたもの,
                数え方: 参加の数え方::全ての辺を数える,
            },
            Self {
                番号: 2,
                選び方: 母集団の選び方::ドメインのクレートの型から関数の役割の型と意味型を除いたもの,
                数え方: 参加の数え方::マーカーへの下位型であるの辺を数えない,
            },
            Self {
                番号: 3,
                選び方: 母集団の選び方::グラフの全ての節点,
                数え方: 参加の数え方::全ての辺を数える,
            },
        ]
    }

    /// 表示の見出し。案の番号と、母集団の選び方と参加の数え方を1文で言う。
    pub fn 見出し(self) -> String {
        format!("案{}({}。{})", self.番号, self.選び方.説明(), self.数え方.説明())
    }

    /// この案でグラフを数える。欠落による弱めは掛けず、グラフの辺だけを見る。
    pub fn グラフで数える(self, グラフ: &設計関係グラフ) -> 案ごとの計測 {
        let (母集団, 内訳) = self.選び方.母集団を採る(グラフ);
        let 参加していない概念一覧 = 母集団
            .iter()
            .filter_map(|概念| {
                let 参照 = 概念.参照を組む();
                self.数え方.参加していない理由を答える(グラフ, &参照).map(|理由| 参加していない概念 { 参照, 理由 })
            })
            .collect();
        案ごとの計測 {
            案: self,
            母集団の件数: 母集団.len(),
            内訳,
            参加していない概念一覧,
        }
    }
}

impl 参加の数え方 {
    // 見出しに書く数え方の1句。
    const fn 説明(self) -> &'static str {
        match self {
            Self::全ての辺を数える => "辺を全部数える",
            Self::マーカーへの下位型であるの辺を数えない => "設計解釈マーカーへの下位型であるの辺を数えない",
        }
    }

    /// その概念がこの数え方で参加していないなら理由を答え、参加しているなら何も答えない。
    fn 参加していない理由を答える(self, グラフ: &設計関係グラフ, 参照: &設計概念への参照) -> Option<参加していない理由> {
        match self {
            Self::全ての辺を数える => グラフ.関係へ1つも参加していないか(参照).then_some(参加していない理由::辺が1本も無い),
            Self::マーカーへの下位型であるの辺を数えない => {
                let 触れる辺: Vec<&設計関係> = グラフ.関係一覧().iter().filter(|関係| &関係.主語 == 参照 || &関係.目的語 == 参照).collect();
                let 本数 = 触れる辺.iter().filter(|関係| マーカーへの下位型であるの辺か(関係)).count();
                if 触れる辺.is_empty() {
                    Some(参加していない理由::辺が1本も無い)
                } else if 本数 == 触れる辺.len() {
                    Some(参加していない理由::マーカーへの下位型であるの辺しか無い { 本数 })
                } else {
                    None
                }
            }
        }
    }
}

// その辺が、設計解釈マーカーを目的語に取る `下位型である` の辺か。
// 受け取る型が外部クレート `blitz_design_verification` の型であり、xtask の側からメソッドを生やせないため自由関数にする。
fn マーカーへの下位型であるの辺か(関係: &設計関係) -> bool {
    関係.種類 == 設計関係の種類::下位型である && 設計解釈マーカーを指す参照か(&関係.目的語)
}
