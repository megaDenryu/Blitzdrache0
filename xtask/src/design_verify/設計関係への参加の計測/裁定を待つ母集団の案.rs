//! 母集団の案とは、「すべてのドメイン概念は設計関係へ参加する」という全称の命題について、母集団を設計関係グラフのどの節点から採るかのことである。
//! このファイルは、オーナーの裁定を待つ2つの案と、案が母集団を採ったときの内訳と、1つの案でグラフを数える工程を持つ。
//!
//! 参加は設計関係の辺と保持する関係の辺で数える(保持する関係を参加に数えるかは Issue #193 の段階3で決める)。
//! 分類(設計解釈マーカーの実装を上位トレイトの宣言で閉じたもの)は辺でないため数えない。
//! 分類を参加に数えると、マーカーを実装した型を母集団にした命題が構造上かならず真になるためである。
//! 数え方が案ごとに違わないため、案は母集団をどの節点から採るかだけを持つ。
//!
//! ドメインのクレートから採る案は、関数の役割の型(`M遷移関数` 等)と、役割に伴う意味型(`遷移成功結果`・`遷移失敗結果`)を外す。
//! この2つはドメインのクレートに定義が在っても、処理の役割の層に置かれた設計語彙であり、ドメイン概念ではないためである
//! (`_doc/設計/設計オントロジー.md` 2.1節・第3節)。外した節点は黙って消さず、内訳へ残して表示する。
//! 定義をたどれずモジュールパスが空の節点はクレート名を持たないため、ドメインのクレートから採る案の母集団には入らない。
//! グラフの全ての節点を採る案はこの節点を含め、検証器がこの節点について未決定を答えるため、内訳へその件数を残す。

use crate::design_model::{ドメインのクレートか, ドメインのクレートの名前一覧, 設計概念, 設計概念の種類, 設計概念への参照, 設計関係グラフ, 関数の役割の型か意味型の見分け};

use super::{参加していない概念, 参加していない理由, 案ごとの計測};

/// 母集団をグラフのどの節点から採るかの案。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 母集団の案 {
    ドメインのクレートの型から関数の役割の型と意味型を除いたもの, // 案1。種類が型であり、定義のモジュールパスがドメインのクレートに在る節点
    グラフの全ての節点,                                           // 案2。種類もクレートも問わない
}

/// 案が母集団を採ったときの内訳。どの案で採ったかによって、表示すべき事実が違う。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 母集団を採った内訳 {
    ドメインのクレートから採った { 外した関数の役割の型と意味型: Vec<設計概念への参照> },
    全ての節点を採った { モジュールパスが空の節点の件数: usize },
}

impl 母集団の案 {
    /// オーナーの裁定を待つ2つの案。表示はこの順に並べる。
    pub const fn 裁定を待つ2つの案() -> [Self; 2] {
        [Self::ドメインのクレートの型から関数の役割の型と意味型を除いたもの, Self::グラフの全ての節点]
    }

    /// 表示の見出し。案の番号と、母集団をどの節点から採るかを1文で言う。
    pub fn 見出し(self) -> String {
        let (番号, 採る節点) = match self {
            Self::ドメインのクレートの型から関数の役割の型と意味型を除いたもの => {
                (1, format!("ドメインのクレート {} の型から、関数の役割の型と意味型を除いたもの", ドメインのクレートの名前一覧().collect::<Vec<_>>().join("・")))
            }
            Self::グラフの全ての節点 => (2, "設計関係グラフの全ての節点".to_string()),
        };
        format!("案{番号}({採る節点}。設計関係と保持する関係の辺を数え、分類は数えない)")
    }

    /// この案でグラフを数える。欠落による弱めは掛けず、グラフの設計関係と保持する関係の辺だけを見る。
    pub fn グラフで数える(self, グラフ: &設計関係グラフ) -> 案ごとの計測 {
        let (母集団, 内訳) = self.母集団を採る(グラフ);
        let 参加していない概念一覧 = 母集団
            .iter()
            .filter_map(|概念| {
                let 参照 = 概念.参照を組む();
                参加していない理由::グラフに尋ねる(グラフ, &参照).map(|理由| 参加していない概念 { 参照, 理由 })
            })
            .collect();
        案ごとの計測 {
            案: self,
            母集団の件数: 母集団.len(),
            内訳,
            参加していない概念一覧,
        }
    }

    // グラフから母集団を採り、採った内訳を添えて返す。
    fn 母集団を採る(self, グラフ: &設計関係グラフ) -> (Vec<&設計概念>, 母集団を採った内訳) {
        match self {
            Self::ドメインのクレートの型から関数の役割の型と意味型を除いたもの => {
                let ドメインのクレートの型 = グラフ.概念一覧().iter().filter(|概念| 概念.種類() == 設計概念の種類::型 && ドメインのクレートか(概念.識別子().クレート名()));
                let (外した, 母集団): (Vec<&設計概念>, Vec<&設計概念>) = ドメインのクレートの型.partition(|概念| 概念.参照を組む().関数の役割の型か意味型を指す参照か());
                let 外した関数の役割の型と意味型 = 外した.iter().map(|概念| 概念.参照を組む()).collect();
                (母集団, 母集団を採った内訳::ドメインのクレートから採った { 外した関数の役割の型と意味型 })
            }
            Self::グラフの全ての節点 => {
                let 母集団: Vec<&設計概念> = グラフ.概念一覧().iter().collect();
                let モジュールパスが空の節点の件数 = 母集団.iter().filter(|概念| 概念.識別子().Rustの項目でありながら定義をたどれていないか()).count();
                (母集団, 母集団を採った内訳::全ての節点を採った { モジュールパスが空の節点の件数 })
            }
        }
    }
}
