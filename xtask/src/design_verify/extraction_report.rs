//! 抽出の結末の内訳の表示。設計関係グラフが何を何件持ち、抽出器が何件の行を読めなかったかを、
//! 種類ごと・抽出元の構文ごと・理由ごとに分けて表示する。
//!
//! **抽出できなかった行を件数だけで済ませず、理由ごとに分けて例を1件ずつ出す。** 総数だけでは、読み手が
//! 「関係が0件である」と「その行を読めなかった」を読み分けられても、なぜ読めなかったかを追えない。
//! 検査した件数を報告することは規約の要求である
//! (`.claude/global-reference/全プロジェクト共通CLAUDE.md`「検査器は解析できなかった入力を黙って対象から外してはならない」)。

use crate::design_model::{抽出できなかった理由, 抽出できなかった行, 抽出の結末, 抽出元の構文, 設計概念, 設計概念の種類, 設計関係, 設計関係の種類};

/// 結末の内訳を標準出力へ表示する。
pub fn 抽出の内訳を表示する(結末: &抽出の結末) {
    概念の内訳を表示する(結末.グラフ.概念一覧());
    関係の内訳を表示する(結末.グラフ.関係一覧());
    抽出できなかった行の内訳を表示する(&結末.抽出できなかった行一覧);
}

// 概念を型・トレイト・処理の3つに分けて数える。
fn 概念の内訳を表示する(概念一覧: &[設計概念]) {
    let 数える = |種類: 設計概念の種類| 概念一覧.iter().filter(|概念| 概念.種類 == 種類).count();
    println!(
        "  概念{}件(型{}件・トレイト{}件・処理{}件)",
        概念一覧.len(),
        数える(設計概念の種類::型),
        数える(設計概念の種類::トレイト),
        数える(設計概念の種類::処理)
    );
}

// 関係を6語の種類ごとに数え、あわせて抽出元の構文ごとに数える。
fn 関係の内訳を表示する(関係一覧: &[設計関係]) {
    println!("  関係{}件", 関係一覧.len());
    for 種類 in 設計関係の種類::最小語彙() {
        let 件数 = 関係一覧.iter().filter(|関係| 関係.種類 == 種類).count();
        println!("    {}: {件数}件", 種類.語());
    }
    for (構文, 件数) in 構文ごとに数える(関係一覧) {
        println!("    抽出元が{}: {件数}件", 構文の呼び名(構文));
    }
}

// 抽出できなかった行を理由の種別ごとに数え、種別ごとに例を1件ずつ出す。
fn 抽出できなかった行の内訳を表示する(行一覧: &[抽出できなかった行]) {
    println!("  抽出できなかった行{}件", 行一覧.len());
    let mut 種別ごと: Vec<(&抽出できなかった理由, usize, &抽出できなかった行)> = Vec::new();
    for 行 in 行一覧 {
        match 種別ごと.iter_mut().find(|(理由, _, _)| 同じ種別か(理由, &行.理由)) {
            Some((_, 件数, _)) => *件数 += 1,
            None => 種別ごと.push((&行.理由, 1, 行)),
        }
    }
    for (_, 件数, 例) in 種別ごと {
        println!("    {件数}件。例: {}", 例.表記());
    }
}

// 抽出元の構文ごとの件数。最初に現れた順に並べ、構文の全件の一覧をこのファイルへ複製しない。
fn 構文ごとに数える(関係一覧: &[設計関係]) -> Vec<(抽出元の構文, usize)> {
    let mut 一覧: Vec<(抽出元の構文, usize)> = Vec::new();
    for 関係 in 関係一覧 {
        match 一覧.iter_mut().find(|(構文, _)| *構文 == 関係.出どころ.構文) {
            Some((_, 件数)) => *件数 += 1,
            None => 一覧.push((関係.出どころ.構文, 1)),
        }
    }
    一覧
}

// 2つの理由が同じ種別か。選択肢が運ぶ値(型名・役割名)の違いは同じ種別として畳む。
fn 同じ種別か(左: &抽出できなかった理由, 右: &抽出できなかった理由) -> bool {
    std::mem::discriminant(左) == std::mem::discriminant(右)
}

// 抽出元の構文の人が読む呼び名。
const fn 構文の呼び名(構文: 抽出元の構文) -> &'static str {
    match 構文 {
        抽出元の構文::上位トレイトの宣言 => "上位トレイトの宣言",
        抽出元の構文::設計解釈マーカーの実装 => "設計解釈マーカーの実装",
        抽出元の構文::構造体のフィールド => "構造体のフィールド",
        抽出元の構文::エンティティの識別子の関連型 => "エンティティの識別子の関連型",
        抽出元の構文::関数の役割の型引数 => "関数の役割の型引数",
    }
}
