//! 抽出した設計関係グラフと抽出の欠けの内訳の表示。設計関係グラフが何を何件持ち(分類の事実を含む)、抽出器が何件の行を読めなかったか、
//! そして同じ識別子へ種類の違う概念が何件来たかを、種類ごと・抽出元の構文ごと・理由ごとに分けて表示する。
//!
//! **抽出できなかった行を件数だけで済ませず、理由ごとに分けて例を1件ずつ出す。** 総数だけでは、読み手が
//! 「関係が0件である」と「その行を読めなかった」を読み分けられても、なぜ読めなかったかを追えない。
//! 検査した件数を報告することは規約の要求である
//! (`.claude/global-reference/全プロジェクト共通CLAUDE.md`「検査器は解析できなかった入力を黙って対象から外してはならない」)。

use blitz_design_verification::節点の分類;

use crate::design_model::{
    保持する関係, 同一性の衝突, 抽出した設計関係グラフと抽出の欠け, 抽出できなかった理由, 抽出できなかった行, 抽出の出どころ, 抽出元の構文, 設計概念, 設計概念の種類, 設計関係の種類, 設計関係グラフ
};

// 同一性の衝突の例を表示する上限。件数は全件を出し、例はこの数までに留める。
const 衝突の例を表示する上限: usize = 5;

/// 抽出したものの内訳を標準出力へ表示する。
pub fn 抽出の内訳を表示する(抽出したもの: &抽出した設計関係グラフと抽出の欠け) {
    概念の内訳を表示する(抽出したもの.グラフ.概念一覧());
    関係の内訳を表示する(&抽出したもの.グラフ);
    分類の内訳を表示する(抽出したもの.グラフ.分類を貸す(), 抽出したもの.グラフ.概念一覧());
    抽出できなかった行の内訳を表示する(&抽出したもの.抽出できなかった行一覧);
    同一性の衝突の内訳を表示する(&抽出したもの.同一性の衝突一覧);
}

// 同じ識別子へ種類の違う概念が来た件数と、その例を表示する。
// 衝突は節点が2つへ割れたことを意味し、割れた両方に辺が散るため、件数を黙って落とすと読み手が反証の読み方を誤る。
fn 同一性の衝突の内訳を表示する(衝突一覧: &[同一性の衝突]) {
    println!("  同一性の衝突{}件", 衝突一覧.len());
    for 衝突 in 衝突一覧.iter().take(衝突の例を表示する上限) {
        println!("    例: {}が{}としても{}としても現れた", 衝突.識別子.表記(), 種類の呼び名(衝突.先に現れた種類), 種類の呼び名(衝突.後から現れた種類));
    }
}

// 設計概念の種類の人が読む呼び名。設計関係への参加の計測の例の表示も同じ呼び名を使う。
pub(super) const fn 種類の呼び名(種類: 設計概念の種類) -> &'static str {
    match 種類 {
        設計概念の種類::型 => "型",
        設計概念の種類::トレイト => "トレイト",
        設計概念の種類::処理 => "処理",
        設計概念の種類::実行時のドメイン概念 => "実行時のドメイン概念",
    }
}

// 概念を型・トレイト・処理の3つに分けて数える。抽出器はRustのソースの項目しか節点にしないため、この3つの合計が概念の件数と一致する。
fn 概念の内訳を表示する(概念一覧: &[設計概念]) {
    let 数える = |種類: 設計概念の種類| 概念一覧.iter().filter(|概念| 概念.種類() == 種類).count();
    println!(
        "  概念{}件(型{}件・トレイト{}件・処理{}件)",
        概念一覧.len(),
        数える(設計概念の種類::型),
        数える(設計概念の種類::トレイト),
        数える(設計概念の種類::処理)
    );
}

// 設計の関係と保持する関係を、別の高さの関係として別々の見出しで数える。設計の関係は4語の種類ごとに、どちらも抽出元の構文ごとに数える。
// 1つの「関係N件」の内訳へ並べないのは、保持するがプリミティブの高さの関係であり、設計の関係と同じ種類の関係として読ませないためである
// (`_doc/設計/設計オントロジー.md` 6.1節・6.6節)。
fn 関係の内訳を表示する(グラフ: &設計関係グラフ) {
    let (設計関係一覧, 保持する関係一覧) = (グラフ.関係一覧(), グラフ.保持する関係一覧());
    println!("  設計の関係{}件", 設計関係一覧.len());
    for 種類 in 設計関係の種類::最小語彙() {
        let 件数 = 設計関係一覧.iter().filter(|関係| 関係.種類 == 種類).count();
        println!("    {}: {件数}件", 種類.語());
    }
    構文ごとの件数を表示する(設計関係一覧.iter().map(|関係| &関係.出どころ));
    println!("  {}関係{}件(プリミティブの高さの関係)", 保持する関係::語(), 保持する関係一覧.len());
    構文ごとの件数を表示する(保持する関係一覧.iter().map(|関係| &関係.出どころ));
}

// 抽出元の構文ごとの件数を1行ずつ表示する。
fn 構文ごとの件数を表示する<'a>(出どころ一覧: impl Iterator<Item = &'a 抽出の出どころ>) {
    for (構文, 件数) in 構文ごとに数える(出どころ一覧) {
        println!("    抽出元が{}: {件数}件", 構文の呼び名(構文));
    }
}

// 分類の事実を種類ごとに数え、分類を持つ概念の件数を出す。分類は辺でないため、関係の件数とは別に出す。
fn 分類の内訳を表示する(分類: &節点の分類, 概念一覧: &[設計概念]) {
    let 事実 = 分類.事実を貸す();
    let 分類を持つ概念の件数 = 概念一覧.iter().filter(|概念| !分類.概念の分類(概念.参照を貸す()).is_empty()).count();
    println!(
        "  分類の事実: マーカーの実装{}件・上位トレイトの宣言{}件。分類を持つ概念{分類を持つ概念の件数}件",
        事実.マーカーの実装一覧().len(),
        事実.上位トレイトの宣言一覧().len()
    );
}

// 抽出できなかった行を理由の種別ごとに数え、種別ごとに例を1件ずつ出す。
fn 抽出できなかった行の内訳を表示する(行一覧: &[抽出できなかった行]) {
    println!("  抽出できなかった行{}件", 行一覧.len());
    let mut 種別ごと: Vec<(&抽出できなかった理由, usize, &抽出できなかった行)> = Vec::new();
    for 行 in 行一覧 {
        match 種別ごと.iter_mut().find(|(理由, _, _)| 同じ種別か(理由, &行.理由)) {
            Some((_, 件数, _)) => *件数 += 1,
            None => 種別ごと.push((&行.理由, 1, 行)),
        }
    }
    for (_, 件数, 例) in 種別ごと {
        println!("    {件数}件。例: {}", 例.表記());
    }
}

// 抽出元の構文ごとの件数。最初に現れた順に並べ、構文の全件の一覧をこのファイルへ複製しない。
fn 構文ごとに数える<'a>(出どころ一覧: impl Iterator<Item = &'a 抽出の出どころ>) -> Vec<(抽出元の構文, usize)> {
    let mut 一覧: Vec<(抽出元の構文, usize)> = Vec::new();
    for 出どころ in 出どころ一覧 {
        match 一覧.iter_mut().find(|(構文, _)| *構文 == 出どころ.構文) {
            Some((_, 件数)) => *件数 += 1,
            None => 一覧.push((出どころ.構文, 1)),
        }
    }
    一覧
}

// 2つの理由が同じ種別か。選択肢が運ぶ値(型名・役割名)の違いは同じ種別としてまとめる。
fn 同じ種別か(左: &抽出できなかった理由, 右: &抽出できなかった理由) -> bool {
    std::mem::discriminant(左) == std::mem::discriminant(右)
}

// 抽出元の構文の人が読む呼び名。
const fn 構文の呼び名(構文: 抽出元の構文) -> &'static str {
    match 構文 {
        抽出元の構文::構造体のフィールド => "構造体のフィールド",
        抽出元の構文::エンティティの識別子の関連型 => "エンティティの識別子の関連型",
        抽出元の構文::関数の役割の型引数 => "関数の役割の型引数",
        抽出元の構文::関数の役割が固定で持つ入力 => "関数の役割が固定で持つ入力",
    }
}
