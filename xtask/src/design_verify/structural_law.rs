//! 検証の入口が検証する構造の法則の命題の集合。設計オントロジーの法則のうち、設計関係グラフだけで問える2件を持つ。
//!
//! 法則の本文を入口の進行へ直接書かないのは、入口が担当するのは検証の段取りと件数の表示であり、
//! どの法則を問うかは別の関心事であるためである。法則を足すのはこのファイルだけで済む。

use crate::design_model::{設計概念の識別子, 設計関係の種類};
use blitz_design_verification::{原子命題, 名前付きの命題, 命題, 命題の集合, 対象集合, 束縛変数, 項};

/// 設計解釈マーカーの正本のモジュールパス。参照: `crates/blitz_design/src/marker.rs`。
const マーカーの正本のモジュールパス: &str = "blitz_design::marker";

/// 構造の法則の命題の集合を組む。
pub fn 構造の法則の命題の集合を組む() -> 命題の集合 {
    命題の集合::生成する(
        "設計関係グラフだけで問える構造の法則",
        vec![
            名前付きの命題::生成する("M状態を名乗る型はM不変データの下位型である", 下位型である法則を組む("M状態", "M不変データ")),
            名前付きの命題::生成する("Mエンティティを名乗る型は設計関係へ1つ以上参加している", 設計関係へ参加する法則を組む("Mエンティティ")),
        ],
    )
}

/// そのマーカーを名乗る全ての概念が、その上位のマーカーの下位型であるという命題。
fn 下位型である法則を組む(マーカー名: &str, 上位のマーカー名: &str) -> 命題 {
    let 束縛 = 束縛変数::生成する("概念");
    命題::全称を組む(
        束縛.clone(),
        対象集合::マーカーを持つ設計概念(マーカー名.to_string()),
        命題::原子から組む(原子命題::設計関係が在る {
            主語: 項::束縛変数(束縛),
            種類: 設計関係の種類::下位型である,
            目的語: 項::名指した概念(設計概念の識別子::生成する(マーカーの正本のモジュールパス, 上位のマーカー名)),
        }),
    )
}

/// そのマーカーを名乗る全ての概念が、設計関係へ1件以上参加しているという命題。
fn 設計関係へ参加する法則を組む(マーカー名: &str) -> 命題 {
    let 束縛 = 束縛変数::生成する("概念");
    命題::全称を組む(
        束縛.clone(),
        対象集合::マーカーを持つ設計概念(マーカー名.to_string()),
        命題::原子から組む(原子命題::設計関係へ1つも参加していない { 概念: 項::束縛変数(束縛) }).否定する(),
    )
}
