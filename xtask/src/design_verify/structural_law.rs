//! 検証の入口が検証する構造の法則の命題の集合。設計解釈マーカーごとの存在理由の公理(Issue #175 のオーナー裁定)の6つを持つ。
//!
//! 存在理由の公理とは、あるマーカーを名乗る型が、関数の役割の宣言を通して処理に使われていることを求める命題のことである。
//! 目的は、コマンド等の型にマーカーが付いているのに、それを使う関数に関数の役割の宣言が漏れている状態を見つけることである
//! (例: `進行の操作` を使う `ゲームの進行段階::次の段階を決める` は意味の上で遷移だが、宣言が無ければ `進行の操作` を消費する処理が現れない)。
//! 公理は、型が処理に直に使われるか、処理に使われる容器の型に保持の経路で持たれることを求める。容器として数えるのは、
//! 同じマーカーを名乗る型(規則の中の規則・状態の中の状態・解釈前の入力の中の解釈前の入力)と、処理に消費される `MParameter` である。
//! **`M状態` の公理だけは、ある1つの処理が同じ状態を消費しかつ次の状態として生成することを求める**(2026-09-27。Issue #175 の第1段階の検収で親が採った指摘)。状態を消費するだけの射影は、
//! 状態から値を取り出すだけで状態を進めないため、状態の存在理由にならない。容器も、そういう遷移に消費される `M状態` だけを数え、`MParameter` を数えない。
//! `MParameter` を容器に数えるのは、意味の決まった値(`Mコマンド`・`M状態`・`M規則` など)を関数へ渡す1つの引数へまとめた型を
//! `MParameter` が名乗る(2026-09-27 のオーナー裁定。`_doc/設計/設計オントロジー.md` 2.6節)ためであり、そうして渡された値も処理に使われている。
//! **`M命令の組` の公理(A6)は、2026-09-28 の命令の組の裁定で足した。** 組が保持するコマンドは、定義の式が組を受け取った処理に消費されると導くため、`Mコマンド` の公理を満たす。
//! しかし組のコマンドが別の宣言でも直に消費されていると、組を受け取る関数に関数の役割の宣言が漏れていても `Mコマンド` の公理は通る。組そのものの消費を求めることで、その漏れを見つける。
//! 容器は `Mコマンド` の公理と同じく処理に消費される `MParameter` である。
//! 「`Mエンティティ` を名乗る型は設計関係へ1つ以上参加している」は、関連型をコンパイラが要求し定義の式が必ず識別するの関係を張るため構造上つねに真であり、置かない。
//! 法則の本文を入口の進行へ直接書かないのは、入口が担当するのは検証の段取りと件数の表示であり、どの法則を問うかは別の関心事であるためである。
//! 参照: `_doc/設計/設計オントロジー.md` 第8節。

