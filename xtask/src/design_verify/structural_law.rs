//! 検証の入口が検証する構造の法則の命題の集合。設計オントロジーの法則のうち、設計関係グラフだけで問える1件を持つ。
//!
//! 法則の本文を入口の進行へ直接書かないのは、入口が担当するのは検証の段取りと件数の表示であり、
//! どの法則を問うかは別の関心事であるためである。法則を足すのはこのファイルだけで済む。

#[cfg(test)]
mod structural_law_tests;

use blitz_design_verification::{原子命題, 名前付きの命題, 命題, 命題の集合, 対象集合, 束縛変数, 項};

/// 構造の法則の命題の集合を組む。
pub fn 構造の法則の命題の集合を組む() -> 命題の集合 {
    // 「M状態を名乗る型はM不変データの一種である」を置かないのは、上位トレイト `M状態: M不変データ` をコンパイラが強制し、分類を上位トレイトの宣言で閉じたラベルにすると常に真になるためである。
    命題の集合::生成する(
        "設計関係グラフだけで問える構造の法則",
        vec![名前付きの命題::生成する("Mエンティティを名乗る型は設計関係へ1つ以上参加している", 設計関係へ参加する法則を組む("Mエンティティ"))],
    )
}

/// そのマーカーを分類に持つ全ての型が、設計関係へ1件以上参加しているという命題。
///
/// **分類は参加に数えない。** 分類は辺でないため、そのマーカーを実装しただけで他の辺を1本も持たない型は、この命題の反例になる。
/// 母集団は分類を持つ型だけであり、`trait M不変エンティティ: Mエンティティ` のようなトレイトは入らない。
fn 設計関係へ参加する法則を組む(マーカー名: &str) -> 命題 {
    let 束縛 = 束縛変数::生成する("概念");
    命題::全称を組む(
        束縛.clone(),
        対象集合::マーカーを持つ設計概念 { マーカー名: マーカー名.to_string() },
        命題::原子から組む(原子命題::設計関係へ1つも参加していない { 概念: 項::束縛変数(束縛) }).否定する(),
    )
}
