/// 構造の法則の命題の集合を組む。
pub fn 構造の法則の命題の集合を組む() -> 命題の集合 {
    let 命題一覧 = 公理の一覧.iter().map(|(名前, 公理)| 名前付きの命題::生成する(名前, 公理.命題を組む())).collect();
    命題の集合::生成する("設計解釈マーカーごとの存在理由の公理", 命題一覧)
}

impl 存在理由の公理 {
    /// マーカーを分類に持つ全ての型について、処理がその型へ関係を張るか、関係を張られる容器が保持の経路でその型を持つ、という全称の命題。
    fn 命題を組む(&self) -> 命題 {
        let 型 = 束縛変数::生成する("型");
        let 直に使われる = self.使い方.処理が使う(&型);
        let 容器に持たれる = self.容器一覧.iter().map(|(容器のマーカー名, 容器の使い方)| 容器に持たれる(容器のマーカー名, *容器の使い方, &型)).collect();
        let 本体 = 命題::選言(非空の命題一覧::先頭と残りから生成する(直に使われる, 容器に持たれる));
        命題::全称を組む(
            型,
            対象集合::マーカーを持つ設計概念 {
                マーカー名: self.マーカー名.to_string()
            },
            本体,
        )
    }
}

// そのマーカーを分類に持つ容器のどれかが、処理にその使い方で使われ、かつ保持の経路で型を持つという存在の命題。
fn 容器に持たれる(容器のマーカー名: &str, 容器の使い方: 処理の使い方, 型: &束縛変数) -> 命題 {
    let 容器 = 束縛変数::生成する(&format!("{容器のマーカー名}の容器"));
    let 保持する = 命題::原子から組む(原子命題::プリミティブな関係の経路が在る {
        主語: 項::束縛変数(容器.clone()),
        種類: プリミティブな関係の種類::保持する,
        目的語: 項::束縛変数(型.clone()),
    });
    let 本体 = 命題::連言(非空の命題一覧::先頭と残りから生成する(容器の使い方.処理が使う(&容器), vec![保持する]));
    命題::存在を組む(
        容器,
        対象集合::マーカーを持つ設計概念 {
            マーカー名: 容器のマーカー名.to_string()
        },
        本体,
    )
}
