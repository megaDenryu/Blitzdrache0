/// 構造の法則の命題の集合を組む。
pub fn 構造の法則の命題の集合を組む() -> 命題の集合 {
    let 命題一覧 = 公理の一覧.iter().map(|(名前, 公理)| 名前付きの命題::生成する(名前, 公理.命題を組む())).collect();
    命題の集合::生成する("設計解釈マーカーごとの存在理由の公理", 命題一覧)
}

impl 存在理由の公理 {
    /// マーカーを分類に持つ全ての型について、処理がその型へ関係を張るか、関係を張られる容器が保持の経路でその型を持つ、という全称の命題。
    fn 命題を組む(&self) -> 命題 {
        let 型 = 束縛変数::生成する("型");
        let 直に使われる = 処理が関係を張る(self.処理の関係, &型);
        let 容器に持たれる = self.容器一覧.iter().map(|(容器のマーカー名, 容器への関係)| 容器に持たれる(容器のマーカー名, *容器への関係, &型)).collect();
        let 本体 = 命題::選言(非空の命題一覧::先頭と残りから生成する(直に使われる, 容器に持たれる));
        命題::全称を組む(
            型,
            対象集合::マーカーを持つ設計概念 {
                マーカー名: self.マーカー名.to_string()
            },
            本体,
        )
    }
}

// その種類の関係の主語に立つ処理のどれかが、束縛した概念へその関係を直に張るという存在の命題。
fn 処理が関係を張る(種類: 設計関係の種類, 概念: &束縛変数) -> 命題 {
    let 処理 = 束縛変数::生成する(&format!("{}を{}処理", 概念.名前(), 種類.語()));
    let 原子 = 原子命題::設計関係が在る {
        主語: 項::束縛変数(処理.clone()),
        種類,
        目的語: 項::束縛変数(概念.clone()),
    };
    命題::存在を組む(処理, 対象集合::全ての設計関係の主語(種類), 命題::原子から組む(原子))
}

// そのマーカーを分類に持つ容器のどれかが、処理にその関係を張られ、かつ保持の経路で型を持つという存在の命題。
fn 容器に持たれる(容器のマーカー名: &str, 容器への関係: 設計関係の種類, 型: &束縛変数) -> 命題 {
    let 容器 = 束縛変数::生成する(&format!("{容器のマーカー名}の容器"));
    let 保持する = 命題::原子から組む(原子命題::保持する関係の経路が在る {
        主語: 項::束縛変数(容器.clone()),
        目的語: 項::束縛変数(型.clone()),
    });
    let 本体 = 命題::連言(非空の命題一覧::先頭と残りから生成する(処理が関係を張る(容器への関係, &容器), vec![保持する]));
    命題::存在を組む(
        容器,
        対象集合::マーカーを持つ設計概念 {
            マーカー名: 容器のマーカー名.to_string()
        },
        本体,
    )
}
