//! 関数の署名の計測の表示。`Display` の実装だけを持つ(トレイト実装の分離)。
//!
//! 手がかりごとの一覧と、状態を受けて同じ状態を返す関数の一覧は、例で切らずに全件を出す。次の法則の候補を読み手が1件ずつ確かめるための材料だからである。
//! 読めなかった箇所は件数を全件出し、例は理由ごとに上限で切る。

use std::fmt;

use super::{宣言の無い関数, 関数の署名の計測};

impl fmt::Display for 関数の署名の計測 {
    fn fmt(&self, 書き先: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(書き先, "  この計測は命題へ接続していない。合否と終了コードに効かない")?;
        let 読めなかった件数: usize = self.読めなかった理由ごとの件数.iter().map(|件| 件.件数).sum();
        writeln!(書き先, "  関数の署名を読めなかった箇所: {読めなかった件数}件")?;
        for 件 in &self.読めなかった理由ごとの件数 {
            writeln!(書き先, "    {}: {}件", 件.呼び名, 件.件数)?;
            for 例 in &件.例一覧 {
                writeln!(書き先, "      例: {例}")?;
            }
        }
        writeln!(書き先, "  関数の役割の宣言に包まれていない関数のうち、遷移の形の手がかりに当たるもの")?;
        for (手がかり, 一覧) in &self.手がかりごとの一覧 {
            writeln!(書き先, "    {}: {}件", 手がかり.見出し(), 一覧.len())?;
            関数の一覧を書く(書き先, 一覧)?;
        }
        writeln!(書き先, "  状態を受けて同じ状態を返すのに関数の役割の宣言が無い関数: {}件", self.状態を受けて同じ状態を返す関数一覧.len())?;
        関数の一覧を書く(書き先, &self.状態を受けて同じ状態を返す関数一覧)
    }
}

// 関数の一覧を、パスと受け手の受け方の1行ずつで書く。
fn 関数の一覧を書く(書き先: &mut fmt::Formatter<'_>, 一覧: &[宣言の無い関数]) -> fmt::Result {
    for 関数 in 一覧 {
        writeln!(書き先, "      {}({})", 関数.パス, 関数.受け手.語())?;
    }
    Ok(())
}
