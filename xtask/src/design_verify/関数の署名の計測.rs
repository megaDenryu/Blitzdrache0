//! 関数の署名の計測(Issue #175 の第2段階の後半)。関数の署名の事実とプリミティブな関係から、次の作業(遷移の形をしているのに関数の役割の宣言が
//! 漏れている関数を見つける法則)の材料を数えて表示する。**この計測は命題へ接続しない。** 合否にも終了コードにも効かない。
//!
//! 数えるのは3つである。1つ目は、抽出器と定義の式が関数の署名を読めなかった箇所の件数を理由ごとに数えたものである。
//! 2つ目は、関数の役割の宣言に包まれていない関数のうち、遷移の形の手がかり(`遷移の形の手がかり`)のどれかに当たるものの一覧である。
//! 3つ目は、状態を受けて同じ状態を返すのに役割の宣言が無い関数だけの一覧であり、次の法則の候補にどれだけ雑音が入るかを見るために出す。
//! 手がかりは型の分類(設計解釈マーカーを上位トレイトの宣言で閉じたもの)と、グラフのプリミティブな関係(関連関数として持つ・引数に取る・返す)から読む。
//! 受け手の受け方と、関数の役割の宣言に包まれたかは、グラフの辺でなく抽出の事実から読む。

