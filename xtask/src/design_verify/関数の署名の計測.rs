use crate::design_model::抽出した設計関係グラフと抽出の欠け;
use blitz_design_verification::受け手の種類;

pub use 手がかり::遷移の形の手がかり;

/// 関数の署名の計測の全体。
#[derive(Debug, Clone)]
pub struct 関数の署名の計測 {
    読めなかった理由ごとの件数: Vec<読めなかった理由ごとの件数>,
    手がかりごとの一覧: Vec<(遷移の形の手がかり, Vec<宣言の無い関数>)>,
    状態を受けて同じ状態を返す関数一覧: Vec<宣言の無い関数>,
}

/// 関数の署名を読めなかった箇所の、理由の呼び名1つぶんの件数と例。
#[derive(Debug, Clone)]
struct 読めなかった理由ごとの件数 {
    呼び名: &'static str,
    件数: usize,
    例一覧: Vec<String>,
}

/// 関数の役割の宣言に包まれていない関数1件。人が読む関数のパスと受け手の受け方を持つ。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 宣言の無い関数 {
    パス: String,
    受け手: 受け手の種類,
}

// 読めなかった箇所の例を理由ごとに残す上限。件数は全件を数える。
const 例を残す上限: usize = 3;

impl 関数の署名の計測 {
    /// 抽出したものを数える。
    pub fn 計測する(抽出したもの: &抽出した設計関係グラフと抽出の欠け) -> Self {
        let 宣言の無い関数一覧 = 手がかり::宣言の無い関数の手がかり一覧(抽出したもの);
        let 一覧を作る = |手がかり: 遷移の形の手がかり| -> Vec<宣言の無い関数> { 宣言の無い関数一覧.iter().filter(|(_, 当たった一覧)| 当たった一覧.contains(&手がかり)).map(|(関数, _)| 関数.clone()).collect() };
        Self {
            読めなかった理由ごとの件数: 読めなかった箇所を数える(抽出したもの),
            手がかりごとの一覧: 遷移の形の手がかり::全部().into_iter().map(|手がかり| (手がかり, 一覧を作る(手がかり))).collect(),
            状態を受けて同じ状態を返す関数一覧: 一覧を作る(遷移の形の手がかり::状態を受けて同じ状態を返す),
        }
    }
}

// 抽出できなかった行のうち、関数の署名を読めなかった行を、理由の呼び名ごとに数える。
fn 読めなかった箇所を数える(抽出したもの: &抽出した設計関係グラフと抽出の欠け) -> Vec<読めなかった理由ごとの件数> {
    let mut 一覧: Vec<読めなかった理由ごとの件数> = Vec::new();
    for 行 in 抽出したもの.抽出できなかった行一覧.iter().filter(|行| 行.関数の署名を読めなかった行か()) {
        let 呼び名 = 行.理由.種別の呼び名();
        let 件 = match 一覧.iter_mut().position(|件| 件.呼び名 == 呼び名) {
            Some(位置) => &mut 一覧[位置],
            None => {
                一覧.push(読めなかった理由ごとの件数 { 呼び名, 件数: 0, 例一覧: Vec::new() });
                let 末尾 = 一覧.len() - 1;
                &mut 一覧[末尾]
            }
        };
        件.件数 += 1;
        if 件.例一覧.len() < 例を残す上限 {
            件.例一覧.push(行.表記());
        }
    }
    一覧
}
