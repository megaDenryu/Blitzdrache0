//! 読み戻し画像の矩形領域と、その中で明度が範囲に入る画素を数える工程。
//! 受け取るのは画像と領域と明度の範囲、返すのは該当画素数である。どこを何色と見なすかは呼び出し元の判定が決め、
//! ここは数えるだけを担う。植生の検収が複数あり、どれも同じ数え方をするため1箇所に置く。

use crate::acceptance::読み戻し画像;

pub struct 画面領域 {
    pub x開始: usize,
    pub x終端: usize,
    pub y開始: usize,
    pub y終端: usize,
}

impl 画面領域 {
    pub fn 画素数(&self) -> u64 {
        let 幅 = self.x終端 - self.x開始;
        let 高さ = self.y終端 - self.y開始;
        u64::try_from(幅 * 高さ).unwrap_or(u64::MAX)
    }
}

pub fn 明度が範囲内の画素を数える(画像: &読み戻し画像, 領域: &画面領域, 下限: u8, 上限: u8) -> Result<u64, String> {
    if 領域.x終端 > 画像.幅() || 領域.y終端 > 画像.高さ() {
        return Err(format!("判定領域が読み戻し画像({})の外にある", 画像.寸法の綴り()));
    }
    let mut 件数 = 0u64;
    for y in 領域.y開始..領域.y終端 {
        for x in 領域.x開始..領域.x終端 {
            let 明度 = 画像.座標の画素(x, y)[0];
            if 明度 >= 下限 && 明度 <= 上限 {
                件数 += 1;
            }
        }
    }
    Ok(件数)
}

/// 領域の全画素が範囲に入ることを確かめ、入った画素数を返す。1つでも外れたら`破れの説明`を添えて失敗にする。
pub fn 全画素が範囲内かを確かめる(
    画像: &読み戻し画像, 領域: &画面領域, 下限: u8, 上限: u8, 破れの説明: &str
) -> Result<u64, String> {
    let 該当数 = 明度が範囲内の画素を数える(画像, 領域, 下限, 上限)?;
    let 期待 = 領域.画素数();
    if 該当数 != 期待 {
        return Err(format!("{破れの説明}: 該当画素{該当数}、領域の画素{期待}"));
    }
    Ok(該当数)
}
