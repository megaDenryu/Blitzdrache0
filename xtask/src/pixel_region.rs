//! 読み戻し画像の矩形領域と、その中で明度が範囲に入る画素を数える工程。
//! 受け取るのは画像と領域と明度の範囲、返すのは該当画素数である。どこを何色と見なすかは呼び出し元の判定が決め、
//! ここは数えるだけを担う。植生の検収が複数あり、どれも同じ数え方をするため1箇所に置く。

use crate::acceptance::{画像の幅, 画像の高さ, 画素の横位置, 画素の縦位置, 読み戻し画像};

pub struct 画面領域 {
    pub x開始: usize,
    pub x終端: usize,
    pub y開始: usize,
    pub y終端: usize,
}

impl 画面領域 {
    pub fn 画素数(&self) -> u64 {
        let 幅 = self.x終端 - self.x開始;
        let 高さ = self.y終端 - self.y開始;
        u64::try_from(幅 * 高さ).unwrap_or(u64::MAX)
    }

    /// この領域が画像の内側に収まるか。幅と高さを別の型で受けるため、縦横を取り違えた比較はコンパイルが拒む。
    pub fn 画像に収まるか(&self, 幅: 画像の幅, 高さ: 画像の高さ) -> bool {
        self.x終端 <= 幅.画素数() && self.y終端 <= 高さ.画素数()
    }

    /// 領域の中の画素の位置を、上の行から順に並べる。走査する側が添字を組み立てないための口である。
    pub fn 位置一覧(&self) -> impl Iterator<Item = (画素の横位置, 画素の縦位置)> {
        let (x開始, x終端) = (self.x開始, self.x終端);
        (self.y開始..self.y終端).flat_map(move |縦| (x開始..x終端).map(move |横| (画素の横位置::生成する(横), 画素の縦位置::生成する(縦))))
    }
}

pub fn 明度が範囲内の画素を数える(画像: &読み戻し画像, 領域: &画面領域, 下限: u8, 上限: u8) -> Result<u64, String> {
    if !領域.画像に収まるか(画像.幅(), 画像.高さ()) {
        return Err(format!("判定領域が読み戻し画像({})の外にある", 画像.寸法の綴り()));
    }
    let mut 件数 = 0u64;
    for (横, 縦) in 領域.位置一覧() {
        let 明度 = 画像.座標の画素(横, 縦)[0];
        if 明度 >= 下限 && 明度 <= 上限 {
            件数 += 1;
        }
    }
    Ok(件数)
}

/// 領域の全画素が範囲に入ることを確かめ、入った画素数を返す。1つでも外れたら`破れの説明`を添えて失敗にする。
pub fn 全画素が範囲内かを確かめる(
    画像: &読み戻し画像, 領域: &画面領域, 下限: u8, 上限: u8, 破れの説明: &str
) -> Result<u64, String> {
    let 該当数 = 明度が範囲内の画素を数える(画像, 領域, 下限, 上限)?;
    let 期待 = 領域.画素数();
    if 該当数 != 期待 {
        return Err(format!("{破れの説明}: 該当画素{該当数}、領域の画素{期待}"));
    }
    Ok(該当数)
}
