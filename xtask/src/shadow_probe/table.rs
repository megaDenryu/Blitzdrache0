//! 標本を条件ごとにまとめて人が読める表にする工程。受け取るのは全標本、出すのは標準出力への行だけである。
//! 判定は行わない。どの条件が速いかの裁定は人が生値と合わせて読む。
//!
//! 代表値に中央値を使い、幅としてp95と最小・最大を並べるのは、実行のあいだで跳ねる標本が混じるためである。
//! 平均を代表値にすると、跳ねた1実行が条件の差を覆い隠す。

use std::collections::BTreeMap;

use blitz_math::{パーセンタイル順位, 昇順に並べた標本列, 順位から添字を選ぶ規則};

use super::record::一標本;

/// この表が添字を選ぶ規則。GPU計器の窓(`crates/blitz_render/src/vulkan/gpu_timing/pass_time_window.rs`)と
/// 同じ規則を使い、表に並ぶ数と計器が報告する数を同じ求め方で揃える。
const 添字を選ぶ規則: 順位から添字を選ぶ規則 = 順位から添字を選ぶ規則::最後の添字を基準にした切り上げ;

pub(super) fn 表示する(標本一覧: &[一標本]) {
    let 条件ごと = 条件ごとにまとめる(標本一覧);
    println!();
    println!("条件 / 標本数 / 合計の中央値 / 合計のp95 / 合計の最小 / 合計の最大 (ミリ秒)");
    for (条件名, 合計一覧) in &条件ごと {
        let mut 写し = 合計一覧.clone();
        let 標本列 = 昇順に並べた標本列::並べ替えて生成する(&mut 写し);
        println!(
            "  {条件名} / {} / {:.4} / {:.4} / {:.4} / {:.4}",
            標本列.件数(),
            順位の値(&標本列, 50.0),
            順位の値(&標本列, 95.0),
            標本列.昇順の値一覧().first().copied().unwrap_or(0.0),
            標本列.最大().unwrap_or(0.0)
        );
    }
    距離区分別を表示する(標本一覧);
}

fn 距離区分別を表示する(標本一覧: &[一標本]) {
    let Some(先頭) = 標本一覧.first() else { return };
    println!("条件 / 太陽高度度 / 太陽方位度 / 距離区分ごとの中央値 (ミリ秒) / 距離区分ごとの投入インデックス数 / 距離区分ごとの可視数");
    let mut 済み: Vec<&str> = Vec::new();
    for 標本 in 標本一覧 {
        if 済み.contains(&標本.条件名.as_str()) {
            continue;
        }
        済み.push(&標本.条件名);
        let 同条件: Vec<&一標本> = 標本一覧.iter().filter(|他| 他.条件名 == 標本.条件名).collect();
        let 中央値一覧: Vec<String> = (0..先頭.距離区分別.len())
            .map(|番号| {
                let mut 写し: Vec<f64> = 同条件.iter().map(|標本| 標本.距離区分別[番号].中央値ミリ秒).collect();
                format!("{:.4}", 順位の値(&昇順に並べた標本列::並べ替えて生成する(&mut 写し), 50.0))
            })
            .collect();
        println!(
            "  {} / {:.3} / {:.3} / [{}] / {:?} / {:?}",
            標本.条件名,
            標本.太陽.高度度,
            標本.太陽.方位度,
            中央値一覧.join(", "),
            標本.投入インデックス数,
            標本.可視数
        );
    }
}

fn 条件ごとにまとめる(標本一覧: &[一標本]) -> BTreeMap<String, Vec<f64>> {
    let mut 表: BTreeMap<String, Vec<f64>> = BTreeMap::new();
    for 標本 in 標本一覧 {
        表.entry(標本.条件名.clone()).or_default().push(標本.合計.中央値ミリ秒);
    }
    表
}

/// 昇順に並んだ標本のうち、指定した順位のパーセンタイル値。標本が1件も無ければ0を表に出す。
fn 順位の値(標本列: &昇順に並べた標本列<'_, f64>, 順位: f32) -> f64 {
    標本列.パーセンタイル値を求める(パーセンタイル順位::百分率から生成する(順位), 添字を選ぶ規則).unwrap_or(0.0)
}
