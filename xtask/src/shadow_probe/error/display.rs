//! 律速切り分けの計測エラーを人が読む1文へ写すトレイト実装。枝ごとに、どの前提がどう破れたかを出す。
//! 実装を型の定義と分けるのは、外部トレイトの実装が型自身の持ち物とは別の軸であるためである。

use std::fmt;

use super::律速切り分けの計測エラー;

impl fmt::Display for 律速切り分けの計測エラー {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::検収の器が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::計測用の構築が失敗した(破れ) => write!(書き手, "{破れ}"),
            Self::シェーダーの一時コピーを作れなかった(破れ) => write!(書き手, "{破れ}"),
            Self::知らない軸を渡された { 語, 選べる軸 } => {
                write!(書き手, "知らない軸である({語})。{選べる軸}のいずれかを指定する")
            }
            Self::振る軸を渡されなかった { 選べる軸 } => write!(書き手, "振る軸を1つ指定する({選べる軸})"),
            Self::引数の次に値が無い { 引数名 } => write!(書き手, "{引数名}の次に値が無い"),
            Self::引数の値を数として読めない { 引数名, 語 } => {
                write!(書き手, "{引数名}の値を数として読めない({語})")
            }
            Self::周回数が零である => write!(書き手, "--roundsは1以上である必要がある"),
            Self::一日内時刻の秒が32ビットに収まらない { 秒 } => {
                write!(書き手, "--time-of-dayの値{秒}が32ビットの非負整数に収まらない")
            }
            Self::検証用ソースアセットを生成できなかった => write!(書き手, "検証用ソースアセットの生成に失敗した"),
            Self::計測世界の実行時アセットを生成できなかった { 世界 } => {
                write!(書き手, "{世界}の実行時アセット生成に失敗した")
            }
            Self::計測世界のアセットが焼かれていない { 世界 } => write!(書き手, "{世界}のアセットが焼かれていない"),
            Self::出力先を作れなかった { パス, 誤り } => {
                write!(書き手, "出力先({})を作れなかった: {誤り}", パス.display())
            }
            Self::実行の標準出力を書けなかった { パス, 誤り } | Self::生値を書けなかった { パス, 誤り } => {
                write!(書き手, "{}を書けなかった: {誤り}", パス.display())
            }
            Self::アプリを起こせなかった { 起こし方, 誤り } => {
                write!(書き手, "{起こし方}を起動できなかった: {誤り}")
            }
            Self::実行が失敗して終わった { 実行番号, 終了状態 } => {
                write!(書き手, "実行{実行番号}が{終了状態}で失敗した")
            }
        }
    }
}
