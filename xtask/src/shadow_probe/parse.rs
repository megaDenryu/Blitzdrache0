//! 子プロセスの終了時報告から1標本ぶんの値を取り出す工程。受け取るのは終了時報告と実行番号と条件名、
//! 返すのは距離区分別の分布と計数を持つ標本である。
//!
//! 行の綴りは`crates/blitz_app/src/reports/gpu_time_table.rs`と`crates/blitz_app/src/reports/draw_issue.rs`の
//! 出力と一致させている。GPU時間の行は「区間名: 平均 (p50 X / p95 Y / 標本N) ms」の形であり、平均は見出しの次の1語、
//! p50とp95は開き括弧や区切りが触れうるためそれぞれの綴りで終わる語の次の1語である。

use super::record::{一標本, 区間の分布, 太陽の角度};
use crate::acceptance::{検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};
use crate::report_parse::距離区分数;

/// 中央値の鍵。分布の行では開き括弧が鍵へ触れているため、末尾一致で探す。
const 中央値の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("p50");
/// 上側95分位の鍵。中央値と同じ行に並び、区切りが触れうるため同じ探し方をする。
const 九十五分位の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("p95");

const 太陽高度の見出し: &str = "太陽高度度:";
const 太陽方位の見出し: &str = "太陽方位度:";
const 距離区分別の合計の区間名: &str = "シャドウ合計";

pub(super) fn 標本を取り出す(報告: &終了時報告, 実行番号: usize, 条件名: &str) -> Result<一標本, 検収エラー> {
    let mut 距離区分別 = Vec::with_capacity(距離区分数);
    let mut 投入インデックス数 = Vec::with_capacity(距離区分数);
    let mut 可視数 = Vec::with_capacity(距離区分数);
    for 番号 in 0..距離区分数 {
        let 名前 = format!("シャドウ距離区分{番号}");
        距離区分別.push(区間の分布を読む(報告, &名前)?);
        投入インデックス数.push(見出しに続く数を読む(報告, &format!("{名前}投入インデックス数:"))?);
        可視数.push(見出しに続く数を読む(報告, &format!("{名前}可視数:"))?);
    }
    Ok(一標本 {
        実行番号,
        条件名: 条件名.to_string(),
        距離区分別,
        合計: 区間の分布を読む(報告, 距離区分別の合計の区間名)?,
        投入インデックス数,
        可視数,
        太陽: 太陽の角度を読む(報告)?,
    })
}

/// `--report-sun-angle`が出す2行。導出はblitz_engineの天空状態が持ち、ここは読むだけである。
fn 太陽の角度を読む(報告: &終了時報告) -> Result<太陽の角度, 検収エラー> {
    Ok(太陽の角度 {
        高度度: 見出しに続く数を読む(報告, 太陽高度の見出し)?,
        方位度: 見出しに続く数を読む(報告, 太陽方位の見出し)?,
    })
}

/// パス別GPU時間の表の1区間ぶんの行。行の頭に立つ区間名は見出しでも鍵でもあるため、同じ綴りを両方に使う。
fn 区間の分布を読む(報告: &終了時報告, 区間名: &str) -> Result<区間の分布, 検収エラー> {
    let 綴り = format!("{区間名}:");
    let 行 = 報告.見出しの1行(&見出しを組む(&綴り))?;
    Ok(区間の分布 {
        平均ミリ秒: 行.鍵に結ばれた数(&鍵を組む(&綴り), 鍵に値が結ばれる形::次の語が値である)?,
        中央値ミリ秒: 行.鍵に結ばれた数(&中央値の鍵, 鍵に値が結ばれる形::この綴りで終わる語の次が値である)?,
        第95百分位ミリ秒: 行.鍵に結ばれた数(&九十五分位の鍵, 鍵に値が結ばれる形::この綴りで終わる語の次が値である)?,
    })
}

/// 見出しで始まる行を探し、その見出しに続く1語を数として読む。読む数の型は受け取る側が決める。
fn 見出しに続く数を読む<数: std::str::FromStr>(報告: &終了時報告, 綴り: &str) -> Result<数, 検収エラー> {
    報告
        .見出しの1行(&見出しを組む(綴り))?
        .鍵に結ばれた数(&鍵を組む(綴り), 鍵に値が結ばれる形::次の語が値である)
}

fn 見出しを組む(綴り: &str) -> 報告の見出し {
    報告の見出し::組み立てた綴りから生成する(綴り.to_string())
}

fn 鍵を組む(綴り: &str) -> 報告の行の鍵 {
    報告の行の鍵::組み立てた綴りから生成する(綴り.to_string())
}
