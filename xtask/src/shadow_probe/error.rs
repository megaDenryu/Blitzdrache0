//! 律速切り分けの計測が返す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。
//! 様式は`acceptance/error.rs`と`depth_prepass_cost/error.rs`に倣う。
//!
//! 検収の器の破れを枝で内包するのは、この入口が起動と報告の読み取りを一続きに通すためである。
//! この入口は合否を判定しないため、判定の破れの枝は持たない。
//!
//! 引数の解釈と支度とファイルの書き出しをここが持つのは、どれも報告の読み取りではないためである。
//! 人が読む1文へ写すのは`display`が持つ。

mod display;

use std::path::PathBuf;

use crate::acceptance::検収エラー;
use crate::asset_generator::世界名;
use crate::release_build::計測用の構築の破れ;
use crate::shader_copy::シェーダーの一時コピーの破れ;

#[derive(Debug)]
pub(super) enum 律速切り分けの計測エラー {
    検収の器が破れた(検収エラー),
    計測用の構築が失敗した(計測用の構築の破れ),
    シェーダーの一時コピーを作れなかった(シェーダーの一時コピーの破れ),
    知らない軸を渡された {
        語: String,
        選べる軸: String,
    },
    振る軸を渡されなかった {
        選べる軸: String,
    },
    引数の次に値が無い {
        引数名: String,
    },
    引数の値を数として読めない {
        引数名: String,
        語: String,
    },
    /// 1周も回さない実行は標本を1つも採らない。
    周回数が零である,
    一日内時刻の秒が32ビットに収まらない {
        秒: usize,
    },
    検証用ソースアセットを生成できなかった,
    計測世界の実行時アセットを生成できなかった {
        世界: 世界名,
    },
    /// 条件が指す世界のアセットが焼かれていない。到達すれば焼く工程と参照する工程で世界の並びが食い違っている。
    計測世界のアセットが焼かれていない {
        世界: 世界名,
    },
    出力先を作れなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    実行の標準出力を書けなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    生値を書けなかった {
        パス: PathBuf,
        誤り: std::io::Error,
    },
    アプリを起こせなかった {
        起こし方: &'static str,
        誤り: std::io::Error,
    },
    実行が失敗して終わった {
        実行番号: usize,
        終了状態: String,
    },
}

impl std::error::Error for 律速切り分けの計測エラー {}

impl From<検収エラー> for 律速切り分けの計測エラー {
    fn from(破れ: 検収エラー) -> Self {
        Self::検収の器が破れた(破れ)
    }
}
