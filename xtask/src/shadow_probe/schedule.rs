//! 条件をどの順で起動するかを決める工程。受け取るのは条件の数と周回数、返すのは条件添字の並びである。
//!
//! 周回ごとに開始条件を1つずつずらす。単純な繰り返し(A B C A B C)では、条件Aが常に周回の先頭に当たり、
//! 周回の先頭だけに効く機材の状態(直前の待機で下がった動作周波数など)が条件Aの値にだけ乗る。
//!
//! 前提: 周回数が条件数の倍数であること。倍数のときに限り、どの条件も同じ回数だけ先頭・中間・末尾に当たる。
//! 倍数でない周回数では開始位置が一巡し切らず、先頭に当たる回数が条件ごとに1回ずれる(3条件4周回では条件0だけが2回)。
//! この前提は`plan::周回数を決める`が切り上げで保証する。ここは受け取った数をそのまま並べるだけであり、丸めは行わない。

/// 周回数と条件数から、起動する条件の添字を順に並べる。条件が0件なら空を返す。
pub(super) fn 交互の順序(条件数: usize, 周回数: usize) -> Vec<usize> {
    if 条件数 == 0 {
        return Vec::new();
    }
    let mut 順序 = Vec::with_capacity(条件数 * 周回数);
    for 周回 in 0..周回数 {
        for 位置 in 0..条件数 {
            順序.push((周回 + 位置) % 条件数);
        }
    }
    順序
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 周回ごとに開始条件がずれる() {
        assert_eq!(交互の順序(3, 3), vec![0, 1, 2, 1, 2, 0, 2, 0, 1]);
    }

    #[test]
    fn どの条件も同じ回数だけ現れる() {
        let 順序 = 交互の順序(4, 4);
        for 添字 in 0..4 {
            assert_eq!(順序.iter().filter(|値| **値 == 添字).count(), 4);
        }
    }

    /// 周回数が条件数の倍数なら、先頭に当たる回数がどの条件も等しい。
    #[test]
    fn 倍数の周回数では先頭に当たる回数が揃う() {
        let 条件数 = 3;
        let 順序 = 交互の順序(条件数, 6);
        for 添字 in 0..条件数 {
            assert_eq!(先頭に当たった回数(&順序, 条件数, 添字), 2);
        }
    }

    /// 倍数でない周回数を渡すと均衡が崩れることの負の対照。この崩れを防ぐのは`plan::周回数を決める`の切り上げである。
    #[test]
    fn 倍数でない周回数では先頭の回数が揃わない() {
        let 条件数 = 3;
        let 順序 = 交互の順序(条件数, 4);
        assert_eq!(先頭に当たった回数(&順序, 条件数, 0), 2);
        assert_eq!(先頭に当たった回数(&順序, 条件数, 1), 1);
        assert_eq!(先頭に当たった回数(&順序, 条件数, 2), 1);
    }

    fn 先頭に当たった回数(順序: &[usize], 条件数: usize, 添字: usize) -> usize {
        順序.iter().step_by(条件数).filter(|値| **値 == 添字).count()
    }

    #[test]
    fn 条件が無ければ空である() {
        assert!(交互の順序(0, 3).is_empty());
    }
}
