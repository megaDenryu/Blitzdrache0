//! 周回数の決め方。担当するのは「指定された周回数と条件数から、実際に回す周回数を1つ決めること」だけである。
//!
//! 周回数を条件数の倍数へ切り上げる。交互の順序は周回ごとに開始条件を1つずらすため、倍数でない周回数では
//! 先頭に当たる回数が条件ごとに1回ずれ、条件の差に「周回の頭だけに効く機材の状態」が混じる。
//! 例えば3条件を4周回すると、開始条件が0・1・2・0となって条件0だけが2回先頭に当たる。
//!
//! 倍数でない指定を型付きエラーで拒まず切り上げるのは、呼び出し元が軸の名前しか知らないためである。
//! どの軸が何条件を持つかは`axis_cases`の台帳にあり、呼び出し元がそれを知らないと`--rounds`を書けない形は使いにくい。
//! 切り上げは黙って行わず、調整したことを呼び出し元が報告する。

/// 指定が無いときの下限。ここから条件数の倍数へ切り上げるため、3条件の軸では6周回になる。
const 既定の下限: usize = 4;

/// 実際に回す周回数。条件数が0なら回すものが無いため0を返す。
pub(in crate::shadow_probe) fn 決める(指定された周回数: Option<usize>, 条件数: usize) -> usize {
    if 条件数 == 0 {
        return 0;
    }
    let 下限 = 指定された周回数.unwrap_or(既定の下限).max(1);
    下限.div_ceil(条件数) * 条件数
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 既定は4以上で条件数の倍数になる。3条件の軸で4のままだと開始条件の回数が揃わない。
    #[test]
    fn 既定は四以上の最小の倍数になる() {
        assert_eq!(決める(None, 3), 6);
        assert_eq!(決める(None, 4), 4);
        assert_eq!(決める(None, 5), 5);
    }

    #[test]
    fn 指定は条件数の倍数へ切り上げる() {
        assert_eq!(決める(Some(4), 3), 6);
        assert_eq!(決める(Some(6), 3), 6);
        assert_eq!(決める(Some(1), 4), 4);
        assert_eq!(決める(Some(9), 4), 12);
    }

    #[test]
    fn 条件が無ければ零を返す() {
        assert_eq!(決める(Some(4), 0), 0);
    }
}
