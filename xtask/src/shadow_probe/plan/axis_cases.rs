//! 軸ごとの条件の台帳。担当するのは「軸の名前からその軸で振る条件の並びを返すこと」だけである。
//! 条件を呼び出し時の文字列でなく台帳で持つのは、同じ軸を何度回しても同じ条件の組で比べられるようにするためであり、
//! 起動指定の綴りをこの1箇所に閉じるためでもある。

use super::{振る軸, 計測世界, 計測条件};

/// 軸ごとの条件の並び。**先頭は必ず既定の条件である。** 交互の順序が周回ごとに開始条件をずらすため、
/// 既定が最初の周回の先頭に来ることで、以降の周回との差から機材の状態の移り変わりを読める。
///
/// 太陽高度の6点は、南中(12時)を挟んで対称な時刻の3対である(7時と17時・8時と16時・9時と15時)。
/// 対の中では高度が等しく方位だけが違うため、**対の中の差は方位の効きである**。対の間の差をそのまま高度の効きと
/// 同一視してはならない(異なる対どうしでは高度と方位の両方が変わり、キャスター配置は東西対称とは限らない)。
/// 高度依存は「各高度で対内の方位差を見積もり、その対内差より対中心間の変化が十分大きく、3高度で傾向が一貫するとき支持する」で判定する。
/// 高度と方位の実測値は条件名でなく各実行の報告から採り、生値と表に残す。
pub(in crate::shadow_probe) fn 軸の条件一覧(軸: 振る軸) -> Vec<計測条件> {
    match 軸 {
        振る軸::解像度 => vec![
            計測条件::起動指定を振る("解像度2048", &[]),
            計測条件::起動指定を振る("解像度1024", &["--shadow-resolution", "1024"]),
            計測条件::起動指定を振る("解像度4096", &["--shadow-resolution", "4096"]),
        ],
        振る軸::キャスター => vec![
            計測条件::起動指定を振る("通常", &[]),
            計測条件::起動指定を振る("個体を影から外す", &["--no-instance-shadow"]),
            計測条件::起動指定を振る("全キャスターを外す", &["--no-shadow-casters"]),
            計測条件::起動指定を振る("最詳細段に固定", &["--no-instance-lod"]),
        ],
        振る軸::余白 => vec![
            計測条件::起動指定を振る("余白60", &[]),
            計測条件::起動指定を振る("余白30", &["--caster-margin", "30"]),
            計測条件::起動指定を振る("余白0", &["--caster-margin", "0"]),
        ],
        振る軸::視点 => vec![
            計測条件::起動指定を振る("既定視点", &[]),
            計測条件::起動指定を振る("方位プラス60度", &["--camera-yaw", "60"]),
            計測条件::起動指定を振る("方位マイナス60度", &["--camera-yaw", "-60"]),
        ],
        振る軸::頂点 => vec![
            計測条件::世界を振る("診断原型の粗い側", 計測世界::頂点診断の粗い世界),
            計測条件::世界を振る("診断原型の細かい側", 計測世界::頂点診断の細かい世界),
        ],
        振る軸::太陽高度 => vec![
            計測条件::時刻を振る("17時", 61_200),
            計測条件::時刻を振る("7時", 25_200),
            計測条件::時刻を振る("16時", 57_600),
            計測条件::時刻を振る("8時", 28_800),
            計測条件::時刻を振る("15時", 54_000),
            計測条件::時刻を振る("9時", 32_400),
        ],
        // 最大影距離の既定は2026-08-03のオーナー裁定で300メートルから225メートルへ短縮した。
        // したがってこの軸の先頭(指定なしの既定条件)は225メートルであり、裁定前の300メートルは明示指定の条件として残す。
        // 影の視距離の軸も最大影距離は指定せず、世界の方針(225メートル)に固定したまま振る。
        // 最大影距離と影の視距離の3水準は、2026-08-03に代表条件(10倍物量・17時・本番の描画)で採ったキャスター距離分布から導いた。
        // 観測は`cargo xtask ow4-bench 4000 --production-draw --time-of-day 61200 --report-caster-distance`であり、
        // そのとき距離区分へ投入された個体の合計は145,313件(距離区分別の可視数は[0, 16771, 40881, 87661])である。
        // カメラからの距離Dで切ったときに残るその合計の比は、D=175mで44.8パーセント・D=200mで56.9パーセント・D=225mで67.4パーセントである。
        // 中心を200mに置くのは、3.1722msから2.0msへ落とすのに要る削減が個体キャスター費用約2.67msの約44パーセントであり、残存約56パーセントがその点に当たるためである。
        // 注意: この残存率が厳密に成り立つのは影の視距離(β)だけである。最大影距離(α)は4距離区分の分割深度と正射影の幅をすべて変えるため、
        // 同じ距離を与えても残る個体数は分布から予測できない。αの実際の残存は各実行が報告する距離区分別の可視数から読む。
        振る軸::最大影距離 => vec![
            計測条件::起動指定を振る("最大影距離225", &[]),
            計測条件::起動指定を振る("最大影距離300", &["--max-shadow-distance", "300"]),
            計測条件::起動指定を振る("最大影距離200", &["--max-shadow-distance", "200"]),
            計測条件::起動指定を振る("最大影距離175", &["--max-shadow-distance", "175"]),
        ],
        振る軸::影の視距離 => vec![
            計測条件::起動指定を振る("切断なし", &[]),
            計測条件::起動指定を振る("影の視距離225", &["--shadow-caster-range", "225"]),
            計測条件::起動指定を振る("影の視距離200", &["--shadow-caster-range", "200"]),
            計測条件::起動指定を振る("影の視距離175", &["--shadow-caster-range", "175"]),
        ],
    }
}
