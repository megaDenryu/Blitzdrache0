//! 軸ごとの条件の台帳。担当するのは「軸の名前からその軸で振る条件の並びを返すこと」だけである。
//! 条件を呼び出し時の文字列でなく台帳で持つのは、同じ軸を何度回しても同じ条件の組で比べられるようにするためであり、
//! 起動指定の綴りをこの1箇所に閉じるためでもある。

use super::{振る軸, 計測条件};

/// 軸ごとの条件の並び。**先頭は必ず既定の条件である。** 交互の順序が周回ごとに開始条件をずらすため、
/// 既定が最初の周回の先頭に来ることで、以降の周回との差から機材の状態の移り変わりを読める。
pub(in crate::shadow_probe) fn 軸の条件一覧(軸: 振る軸) -> Vec<計測条件> {
    match 軸 {
        振る軸::解像度 => vec![
            計測条件 {
                名前: "解像度2048",
                起動指定: &[],
            },
            計測条件 {
                名前: "解像度1024",
                起動指定: &["--shadow-resolution", "1024"],
            },
            計測条件 {
                名前: "解像度4096",
                起動指定: &["--shadow-resolution", "4096"],
            },
        ],
        振る軸::キャスター => vec![
            計測条件 {
                名前: "通常", 起動指定: &[]
            },
            計測条件 {
                名前: "個体を影から外す",
                起動指定: &["--no-instance-shadow"],
            },
            計測条件 {
                名前: "全キャスターを外す",
                起動指定: &["--no-shadow-casters"],
            },
            計測条件 {
                名前: "最詳細段に固定",
                起動指定: &["--no-instance-lod"],
            },
        ],
        振る軸::余白 => vec![
            計測条件 {
                名前: "余白60",
                起動指定: &[],
            },
            計測条件 {
                名前: "余白30",
                起動指定: &["--caster-margin", "30"],
            },
            計測条件 {
                名前: "余白0",
                起動指定: &["--caster-margin", "0"],
            },
        ],
        振る軸::視点 => vec![
            計測条件 {
                名前: "既定視点",
                起動指定: &[],
            },
            計測条件 {
                名前: "方位プラス60度",
                起動指定: &["--camera-yaw", "60"],
            },
            計測条件 {
                名前: "方位マイナス60度",
                起動指定: &["--camera-yaw", "-60"],
            },
        ],
    }
}
