//! 出どころの違う2つの計数の突き合わせ。受け取るのは1回の実行の計数報告、返すのは合否である。
//!
//! レンダラーは積んだ描画発行のインスタンス数を数え、エンジンの可視個体の選別は判定した個体を数える。
//! 可視判定へ登録されるのはインスタンス群だけであり、通常メッシュと地形はどのパスでも常に全個体が描かれるため、
//! パスごとに「レンダラーの可視数 = 可視個体の選別の可視数 + 群でない個体数」が成り立つ。群でない個体数は2つの候補数の差である。
//! この等式が破れることは、判定した集合と実際に描いた集合が食い違ったか、どちらかの計器が数え落としたことを意味する。
//! 設計正本が第6段の検収へ求める「発行数とID数の一致」がこの検査である
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」)。

use crate::acceptance::{判定の名前, 判定の破れ};
use crate::report_parse::{可視個体の選別の計数, 計数報告};

pub fn 計数の整合を検査する(実行名: &str, 計数: &計数報告) -> Result<(), 判定の破れ> {
    可視個体の選別の候補数の判定名(実行名).上限を課す(計数.可視個体の選別.候補数, 計数.シーン.候補数)?;
    // 注意: 直前の判定が可視個体の選別の候補数はレンダラーの候補数を上回らないことを課すため、この引き算は破れない。
    let 群でない個体数 = 計数.シーン.候補数 - 計数.可視個体の選別.候補数;
    let mut 一覧 = vec![("シーンパス".to_string(), 計数.シーン.可視数, 計数.可視個体の選別.シーン可視数)];
    for (番号, (距離区分, 可視個体の選別の可視数)) in 計数.距離区分別のシャドウ.iter().zip(&計数.可視個体の選別.距離区分別の可視数).enumerate()
    {
        一覧.push((format!("シャドウ距離区分{番号}"), 距離区分.可視数, *可視個体の選別の可視数));
    }
    for (パス名, レンダラーの可視数, 可視個体の選別の可視数) in 一覧 {
        let 判定名 = レンダラーの可視数の判定名(実行名, &パス名, 可視個体の選別の可視数, 群でない個体数);
        判定名.一致を課す(レンダラーの可視数, 可視個体の選別の可視数 + 群でない個体数)?;
    }
    Ok(())
}

/// 距離区分別の可視個体の選別が実際に効いていること。少なくとも1つの距離区分の可視数が群の候補数を下回り、全距離区分の合計が
/// 「距離区分数×候補数」(どの距離区分も全個体を描く形)を下回ることを見る。
/// 距離区分別の可視数の和で見ないのは、和が複数の距離区分へ属する個体を重複して数えるためである。ここで見るのは
/// 「絞られたかどうか」だけであり、落ちた個体が正しいかどうかは絵のバイト一致と距離区分の和集合の可視数が受け持つ。
pub fn 距離区分別に絞られたことを検査する(実行名: &str, 計数: &計数報告) -> Result<(), 判定の破れ> {
    let 可視個体の選別 = &計数.可視個体の選別;
    let 絞られた距離区分数 = 可視個体の選別
        .距離区分別の可視数
        .iter()
        .filter(|可視数| **可視数 < 可視個体の選別.候補数)
        .count();
    if 絞られた距離区分数 == 0 {
        return Err(絞られた距離区分の判定名(実行名, 可視個体の選別).あるはずのものが無い破れ());
    }
    let 距離区分別の合計: u64 = 可視個体の選別.距離区分別の可視数.iter().sum();
    let 全距離区分が全個体を描く数 = 可視個体の選別.候補数 * u64::try_from(可視個体の選別.距離区分別の可視数.len()).unwrap_or(1);
    距離区分別の合計の判定名(実行名, 距離区分別の合計, 全距離区分が全個体を描く数)
        .真であることを課す(距離区分別の合計 < 全距離区分が全個体を描く数)
}

fn 可視個体の選別の候補数の判定名(実行名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{実行名}の可視個体の選別の候補数(レンダラーの候補数を上回ってはならない)"))
}

fn レンダラーの可視数の判定名(
    実行名: &str, パス名: &str, 可視個体の選別の可視数: u64, 群でない個体数: u64
) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{実行名}の{パス名}でレンダラーが数えた可視数(可視個体の選別の可視数{可視個体の選別の可視数}と群でない個体{群でない個体数}体の和になるはずである)"
    ))
}

fn 絞られた距離区分の判定名(実行名: &str, 可視個体の選別: &可視個体の選別の計数) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{実行名}で候補{}体から絞られた距離区分(距離区分別の可視数{:?})",
        可視個体の選別.候補数, 可視個体の選別.距離区分別の可視数
    ))
}

/// 比べの形を上限でなく真偽で課すのは、この判定が合計と全個体を描く数が等しい実行を破れの側へ置くためである。
/// 上限の口は等号を通すため、そのまま置き換えるとどの距離区分も絞っていない実行が境界でだけ通る。
fn 距離区分別の合計の判定名(
    実行名: &str, 距離区分別の合計: u64, 全距離区分が全個体を描く数: u64
) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{実行名}の距離区分別の可視数の合計{距離区分別の合計}が全距離区分で全個体を描く{全距離区分が全個体を描く数}を下回ること"
    ))
}
