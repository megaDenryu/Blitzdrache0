//! 出どころの違う2つの計数の突き合わせ。受け取るのは1回の実行の計数報告、返すのは合否である。
//!
//! レンダラーは積んだ描画発行のインスタンス数を数え、エンジンの群選択は判定した個体を数える。
//! 可視判定へ登録されるのはインスタンス群だけであり、通常メッシュと地形はどのパスでも常に全個体が描かれるため、
//! パスごとに「レンダラーの可視数 = 群選択の可視数 + 群でない個体数」が成り立つ。群でない個体数は2つの候補数の差である。
//! この等式が破れることは、判定した集合と実際に描いた集合が食い違ったか、どちらかの計器が数え落としたことを意味する。
//! 設計正本が第6段の検収へ求める「発行数とID数の一致」がこの検査である
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の帯別区間(4区分並べの後継)」)。

use crate::report_parse::計数報告;

pub fn 計数の整合を検査する(実行名: &str, 計数: &計数報告) -> Result<(), String> {
    let 群でない個体数 = 計数.シーン.候補数.checked_sub(計数.群選択.候補数).ok_or_else(|| {
        format!(
            "{実行名}の群選択の候補数{}がレンダラーの候補数{}を上回った",
            計数.群選択.候補数, 計数.シーン.候補数
        )
    })?;
    let mut 一覧 = vec![("シーンパス".to_string(), 計数.シーン.可視数, 計数.群選択.シーン可視数)];
    for (番号, (帯, 群選択の可視数)) in 計数.帯別シャドウ.iter().zip(&計数.群選択.帯別可視数).enumerate() {
        一覧.push((format!("シャドウ帯{番号}"), 帯.可視数, *群選択の可視数));
    }
    for (パス名, レンダラーの可視数, 群選択の可視数) in 一覧 {
        let 期待 = 群選択の可視数 + 群でない個体数;
        if レンダラーの可視数 != 期待 {
            return Err(format!(
                "{実行名}の{パス名}で2つの計器が食い違った: レンダラーの可視数{レンダラーの可視数}、群選択の可視数{群選択の可視数}と群でない個体{群でない個体数}体の和{期待}"
            ));
        }
    }
    Ok(())
}

/// 帯別カリングが実際に効いていること。少なくとも1つの帯の可視数が群の候補数を下回り、全帯の合計が
/// 「帯数×候補数」(どの帯も全個体を描く形)を下回ることを見る。
/// 帯別の可視数の和で見ないのは、和が複数の帯へ属する個体を重複して数えるためである。ここで見るのは
/// 「絞られたかどうか」だけであり、落ちた個体が正しいかどうかは絵のバイト一致と帯和集合可視数が受け持つ。
pub fn 帯別に絞られたことを検査する(実行名: &str, 計数: &計数報告) -> Result<(), String> {
    let 群選択 = &計数.群選択;
    let 絞られた帯数 = 群選択.帯別可視数.iter().filter(|可視数| **可視数 < 群選択.候補数).count();
    if 絞られた帯数 == 0 {
        return Err(format!(
            "{実行名}でどの帯も候補{}体から絞られていない: 帯別可視数{:?}",
            群選択.候補数, 群選択.帯別可視数
        ));
    }
    let 帯別合計: u64 = 群選択.帯別可視数.iter().sum();
    let 全帯が全個体を描く数 = 群選択.候補数 * u64::try_from(群選択.帯別可視数.len()).unwrap_or(1);
    if 帯別合計 >= 全帯が全個体を描く数 {
        return Err(format!(
            "{実行名}の帯別可視数の合計{帯別合計}が全帯で全個体を描く{全帯が全個体を描く数}を下回っていない"
        ));
    }
    Ok(())
}
