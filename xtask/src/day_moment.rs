//! 一日の代表時刻の表。担当するのは「絵を撮る4つの時刻の名前と一日内の秒を1箇所に置く」ことだけである。
//!
//! 一日内の秒は既定の一日の長さ(86400秒)での値である。夜明けと夕方はどちらも太陽高度がちょうど0であり、
//! 方位だけが東と西で反対になる。`--report-sky-state`の代表位相と同じ4つを選んであるため、同じ場面を絵でも数でも語れる。
//!
//! 表を検収の入口ごとに持たないのは、複数の入口が同じ一日の同じ位相を撮るためである。片方だけが秒を変えると、
//! 2つの入口の絵が別の時刻のものになり、並べて見比べる根拠が消える。
//!
//! `太陽が地平線より上か`は、太陽高度がちょうど0の夜明けと夕方も真として扱う。偽になるのは夜だけであり、
//! そのとき地面を照らすのは間接光だけになる。

pub struct 代表時刻 {
    pub 名前: &'static str,       // 報告に出す名前
    pub ファイル名: &'static str, // ダンプのファイル名に使う名前。パスはASCIIで保つ
    pub 一日内秒: &'static str,
    pub 太陽が地平線より上か: bool,
}

