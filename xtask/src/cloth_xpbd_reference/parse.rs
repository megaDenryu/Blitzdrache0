//! 終了時報告から参照比較の観測を読む工程。受け取るのは終了時報告、返すのは題材と差と拘束違反の観測である。
//! 行の綴りは`crates/blitz_app/src/reports/cloth_xpbd_reference/lines.rs`の出力と一致させ、行はどれも「見出し 鍵=値 鍵=値 …」の形である。
//! 差の行が無い実行は、参照計算が再現できない条件(自己衝突・読み戻しの失敗)へ入ったことを意味し、その不在が失敗として現れる。

use crate::acceptance::{報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

const 題材の見出し: 報告の見出し = 報告の見出し::定数から生成する("布XPBD参照比較");
const 差の見出し: 報告の見出し = 報告の見出し::定数から生成する("布XPBD参照比較の差");
const 拘束違反の見出し: 報告の見出し = 報告の見出し::定数から生成する("布XPBD参照比較の拘束違反");

pub(super) struct 参照比較の観測 {
    pub(super) 刻み数: u32,
    pub(super) 反復回数: u32,
    pub(super) コンプライアンス: f64,
    pub(super) 色の数: u32,
    pub(super) 位置の最大差: f64,
    pub(super) 乗数の最大差: f64,
    pub(super) 全て有限か: bool,
    pub(super) gpuの拘束違反: f64,
    pub(super) cpuの拘束違反: f64,
    pub(super) 検証件数: u64,
}

impl 参照比較の観測 {
    pub(super) fn 要約(&self, 名前: &str) -> String {
        format!(
            "{名前}(コンプライアンス{:.0e})は刻み{}本×反復{}回・{}色で、CPU参照との位置の最大差{:.3e}メートル・乗数の最大差{:.3e}、拘束違反はGPU{:.3e}・CPU{:.3e}",
            self.コンプライアンス,
            self.刻み数,
            self.反復回数,
            self.色の数,
            self.位置の最大差,
            self.乗数の最大差,
            self.gpuの拘束違反,
            self.cpuの拘束違反
        )
    }
}

pub(super) fn 参照比較を読む(報告: &終了時報告) -> Result<参照比較の観測, 検収エラー> {
    let 題材 = 報告.見出しの1行(&題材の見出し)?;
    let 差 = 報告.見出しの1行(&差の見出し)?;
    let 拘束違反 = 報告.見出しの1行(&拘束違反の見出し)?;
    Ok(参照比較の観測 {
        刻み数: 数(&題材, "刻み数")?,
        反復回数: 数(&題材, "反復回数")?,
        コンプライアンス: 数(&題材, "コンプライアンス")?,
        色の数: 数(&題材, "色の数")?,
        位置の最大差: 数(&差, "位置の最大差")?,
        乗数の最大差: 数(&差, "乗数の最大差")?,
        全て有限か: 綴り(&差, "全て有限")? == "はい",
        gpuの拘束違反: 数(&拘束違反, "GPUの拘束違反の二乗平均平方根")?,
        cpuの拘束違反: 数(&拘束違反, "CPUの拘束違反の二乗平均平方根")?,
        検証件数: 報告.検証層の指摘件数()?,
    })
}

fn 数<数: std::str::FromStr>(行: &報告の行, 鍵: &str) -> Result<数, 検収エラー> {
    行.鍵に結ばれた数(
        &報告の行の鍵::組み立てた綴りから生成する(鍵.to_string()),
        鍵に値が結ばれる形::等号の後ろが値である,
    )
}

fn 綴り(行: &報告の行, 鍵: &str) -> Result<String, 検収エラー> {
    行.鍵に結ばれた綴り(
        &報告の行の鍵::組み立てた綴りから生成する(鍵.to_string()),
        鍵に値が結ばれる形::等号の後ろが値である,
    )
}
