//! 参照比較とGPU時間の判定。受け取るのは観測、返すのは合否である。
//!
//! 許容差の根拠: 位置は2メートル以下であり単精度の刻みは2.4e-7メートル、刻み12本×反復4回=48回の射影で演算順の違いが積み重なった量は
//! `xpbd-solver-bench`の実測(規則格子の彩色で3.8e-7、不規則で9.6e-6メートル)の桁であり、その10倍の1e-4メートルを許容にする。
//! 乗数は硬い吊るし布で最大3e-4キログラム・メートルの桁であり、実測の差(4e-9)の200倍余りの1e-6を許容にする。
//! 布の参照計算は速度をベルレ形(位置と刻みの開始の位置の差)で持ち、GPUは速度を別に持つため、両者の差にはその丸めの差も入る。
//! GPU時間の上限は評価軸3.1のシミュレーション(コンピュート)の枠3.0ミリ秒である。布はその一部だが、枠を1つの布で越えれば予算の見直しである。
//! 布の刻み幅は時間の規律の正本(`crates/blitz_app/src/game/step_seconds.rs`)と同じ値でなければならず、ここが持つ写しは
//! `cargo xtask conform`の定数の組(`conform/shader_constant/table/time_step.rs`)が正本と突き合わせる。報告の刻み幅は単精度で
//! 出るため、倍精度の写しとの差は単精度の丸め(1.2e-10秒)であり、その100倍を許容にする。

use super::gpu_time::布の一刻みのGPU時間;
use super::parse::参照比較の観測;
use crate::acceptance::{判定の名前, 判定の破れ};

const 位置の許容メートル: f64 = 1.0e-4;
const 乗数の許容: f64 = 1.0e-6;
const シミュレーションの枠ミリ秒: f64 = 3.0;
const 正本の基本刻みの秒: f64 = 1.0 / 60.0;
const 刻み幅の許容秒: f64 = 1.0e-8;

pub(super) fn 参照比較を判定する(名前: &str, 観測: &参照比較の観測) -> Result<(), 判定の破れ> {
    判定名(名前, "validationの指摘件数").零件であることを課す(観測.検証件数)?;
    判定名(名前, "読み戻した位置と乗数の有限性").真であることを課す(観測.全て有限か)?;
    判定名(名前, "進めた刻み数(比較のフレーム数と同じ本数だけ進んでいる)").正であることを課す(f64::from(観測.刻み数))?;
    判定名(名前, "布の刻み幅と時間の規律の正本の基本刻みとの差").上限を課す((観測.刻み幅の秒 - 正本の基本刻みの秒).abs(), 刻み幅の許容秒)?;
    判定名(名前, "CPU参照との位置の最大差").上限を課す(観測.位置の最大差, 位置の許容メートル)?;
    判定名(名前, "CPU参照との乗数の最大差").上限を課す(観測.乗数の最大差, 乗数の許容)?;
    判定名(名前, "GPUの拘束違反の二乗平均平方根").有限であることを課す(観測.gpuの拘束違反)?;
    判定名(名前, "CPUの拘束違反の二乗平均平方根").有限であることを課す(観測.cpuの拘束違反)
}

pub(super) fn 一刻みのgpu時間を判定する(一刻み: &布の一刻みのGPU時間) -> Result<(), 判定の破れ> {
    for (パス名, 値) in &一刻み.パス別のp50ミリ秒 {
        判定名("gpu_time", &format!("{パス名}のp50")).有限であることを課す(*値)?;
    }
    判定名("gpu_time", "布のパスのp50の合計").上限を課す(一刻み.合計のp50ミリ秒, シミュレーションの枠ミリ秒)
}

fn 判定名(名前: &str, 量の名前: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{名前}の実行の{量の名前}"))
}
