//! 抽出の成果と、抽出した設計関係グラフと抽出の欠け。5つの抽出の規則が同じ形の成果を返し、入口がそれを1つへ併せて
//! 設計関係グラフと抽出の欠けへ組む。成果は関係を持たず、プリミティブな事実を持つ。関係は組むときに定義の式を評価して導く(Issue #193 の段階2)。
//!
//! 2つの型を分けるのは寿命が違うためである。成果は規則1つぶんの途中の値であり、規則を跨いで併せる操作を持つ。
//! 抽出した設計関係グラフと抽出の欠けは入口が1度だけ返す答えであり、節点の重複を1つにまとめたグラフを持つ。
//!
//! 成果はプリミティブな事実と別に分類の事実(マーカーの実装と上位トレイトの宣言)も運ぶ。分類は辺ではなく、グラフが節点のラベルとして閉じて持つためである。
//! 概念を成果が運ぶのは、分類の事実の端点がトレイトか型かを知っているのが抽出した規則の側だからである。
//! 型の定義と関数の役割の宣言が立てる節点は事実が、導いた関係の端点は定義の式の評価器が運ぶ。入口は種類を決め直さない。
//! 定義の式の評価器が導けなかった箇所(導出の欠け)は、抽出できなかった行へ写して同じ一覧で数える。
//! 同じ識別子へ種類の違う概念が来たときは、グラフの組み立てが両方を節点として残して衝突に数え、この値がその一覧を運ぶ。
//! この値が衝突を運ぶのは、入口の表示が件数と例を出すためと、検証器へ渡す `関係を落とした抽出の欠落` をこの値から組むためである。
//! 表示だけでは証明の健全性が回復しない。辺がグラフへ入らないまま「辺が無い」を根拠に反証すると、否定の下でその反証が
//! 反転して証明済みになるため、この値は欠落を検証器へ渡せる形へ写すメソッドを持つ。

