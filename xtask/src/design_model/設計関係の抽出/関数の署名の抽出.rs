//! 抽出の規則6: 関数の項目から、関数の署名の事実を抽出する工程(Issue #175 の第2段階)。
//! 受け取るのは抽出対象のソース群、返すのは関数の署名の事実と、読めなかった関数の行を持つ成果である。関係は出さない。
//!
//! 読むのは、項目の位置(モジュールの直下と、`impl … { }` と `trait … { }` の本体の直下)に書いた `fn` だけである。項目の位置は、ファイルの行を頭から読んで
//! 開いている波括弧が何の本体かを数えて決める(`関数を持つ位置`)。関数の本体や構造体・マクロの本体の中に書いた `fn` は、抽出器が項目の位置として読まないため、
//! 黙って外さずに `項目の位置でない関数である` として数える。
//!
//! 処理の識別子は、関数の役割の宣言の事実と同じ組み方(その `fn` を書いたファイルのモジュールパス・所有者の名前・関数の名前)で作る。
//! 役割の宣言が包んだ関数と、その関数の署名の事実が同じ節点になり、2つの節点へ割れないためである。
//! `impl` の本体の関数の型の表記は、`Self` を実装の対象の型の表記へ置き換える。`trait` の本体の `Self` は実装する型の総称であり名指す型が無いため、
//! 置き換えずに型引数の名前として扱い、定義の式が読めない表記として数える。

use super::抽出できなかった行の定義::{抽出できなかった理由, 抽出できなかった行};
use super::抽出の成果と欠け::抽出の成果;
use super::抽出対象のソース群の定義::抽出対象のソース群;
use super::関数の見出しの読み取り::{読んだ関数の見出し, 関数の予約語より後ろ, 関数の見出しを読む};
use super::関数を持つ位置::{関数の持ち主, 関数を持つ位置の走査};
use crate::conform::design_ontology::identifier_boundary::識別子として現れる位置一覧;
use crate::conform::design_ontology::module_path::モジュールパス;
use crate::design_model::{Rustの項目の種類, 設計概念, 設計概念の識別子};
use blitz_design_verification::{事実の出どころ, 型の表記, 関数の所有者, 関数の署名の事実};
use std::path::Path;

pub fn 関数の署名から抽出する(ソース群: &抽出対象のソース群) -> 抽出の成果 {
    let mut 成果 = 抽出の成果::default();
    for (パス, 行一覧) in ソース群.ファイル一覧() {
        let mut 走査 = 関数を持つ位置の走査::生成する(モジュールパス::ファイルのパスから求める(パス));
        for (添字, 行) in 行一覧.iter().enumerate() {
            if 関数の予約語より後ろ(行).is_some() {
                match 走査.いまの関数の持ち主() {
                    Some(持ち主) => 成果.併せる(関数の署名を抽出する(パス, 行一覧, 添字, &持ち主)),
                    None => {
                        let 理由 = 抽出できなかった理由::項目の位置でない関数である { 関数名: 関数名を採る(行) };
                        成果.抽出できなかった行一覧.push(抽出できなかった行::生成する(パス, 添字 + 1, 理由));
                    }
                }
            }
            走査.行を読む(行一覧, 添字);
        }
    }
    成果
}

// 項目の位置の `fn` の行1つから、関数の署名の事実1件か、読めなかった1件を持つ成果を組む。
fn 関数の署名を抽出する(パス: &Path, 行一覧: &[String], 添字: usize, 持ち主: &関数の持ち主) -> 抽出の成果 {
    let mut 成果 = 抽出の成果::default();
    match 関数の見出しを読む(行一覧, 添字) {
        Ok(見出し) => 成果.事実.関数の署名一覧.push(署名の事実を組む(
            見出し,
            持ち主,
            事実の出どころ {
                パス: パス.to_path_buf(), 行番号: 添字 + 1
            },
        )),
        Err(理由) => 成果.抽出できなかった行一覧.push(抽出できなかった行::生成する(パス, 添字 + 1, 抽出できなかった理由::関数の見出しを読めない { 理由 })),
    }
    成果
}

// 読んだ見出しと持ち主から事実を組む。型の表記は、持ち主と関数の型引数を有効な型引数として持ち、`impl` の本体なら `Self` を対象の型の表記へ置き換える。
fn 署名の事実を組む(見出し: 読んだ関数の見出し, 持ち主: &関数の持ち主, 出どころ: 事実の出どころ) -> 関数の署名の事実 {
    let 有効な型引数名一覧: Vec<String> = 持ち主.型引数名一覧.iter().chain(&見出し.型引数名一覧).cloned().collect();
    let 表記にする = |綴り: &str| 型の表記::生成する(&持ち主.自分の型の予約語を対象の型の表記へ置き換える(綴り), 有効な型引数名一覧.clone());
    let 識別子 = 設計概念の識別子::Rustの項目として生成する(持ち主.モジュールパス.表記(), &見出し.名前).所有者を添える(持ち主.所有者の名前一覧());
    関数の署名の事実 {
        処理: 設計概念::Rustの項目として生成する(識別子, Rustの項目の種類::処理),
        所有者: 持ち主.所有者.clone(),
        受け手: 見出し.受け手,
        引数の表記一覧: 見出し.引数の表記一覧.iter().map(|綴り| 表記にする(綴り.as_str())).collect(),
        戻り値の表記: 見出し.戻り値の表記.as_deref().map(表記にする),
        出どころ,
    }
}

impl 関数の持ち主 {
    // 処理の識別子へ添える所有者の名前の並び。自由関数は空である。
    fn 所有者の名前一覧(&self) -> Vec<String> {
        match &self.所有者 {
            関数の所有者::自由関数 => Vec::new(),
            関数の所有者::型(_) | 関数の所有者::トレイト(_) => vec![self.名前.clone()],
        }
    }

    // `impl` の本体なら、綴りの中の識別子の `Self` を実装の対象の型の表記へ置き換える。それ以外は綴りのままである。
    fn 自分の型の予約語を対象の型の表記へ置き換える(&self, 綴り: &str) -> String {
        let 関数の所有者::型(対象) = &self.所有者 else {
            return 綴り.to_string();
        };
        let mut 置き換えた = 綴り.to_string();
        for 位置 in 識別子として現れる位置一覧(綴り, "Self").into_iter().rev() {
            置き換えた.replace_range(位置..位置 + "Self".len(), 対象.綴り());
        }
        置き換えた
    }
}

// 項目の位置でない `fn` の行から、報告に出す関数の名前を採る。
fn 関数名を採る(行: &str) -> String {
    関数の予約語より後ろ(行).map(crate::conform::design_ontology::line_matching::先頭の識別子).unwrap_or_default()
}
