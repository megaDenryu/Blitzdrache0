//! 型の定義をたどれなかった表記か実装の対象があるとき、定義をたどれた同じ名前の型の節点への問いが、辺か分類の不在から反証されず未決定になることを固定する回帰試験。
//!
//! 抽出器がある場所から型の定義をたどれないと、そこから導いた辺か分類はモジュールパスが空の節点へ付く。定義をたどれた節点への問いはその空の節点に触れないため、
//! 止めが無いと辺か分類の不在を答える。止めは構造の検証器の1か所(同じ名前の空の節点が在れば未決定)にあり、この試験は経路ごとにそれを確かめる。
//! 経路は、関係の頭の端点の表記・マーカーの実装の対象・`Mエンティティ` の実装の対象の3つである。規則の本体の途中の表記は
//! `抽出の成果と欠け/規則の本体の途中の未解決の試験.rs` が確かめる。どの経路も、取り込みを書いた対照が証明済みになることを並べて確かめる。
//! 辿る経路の途中の節点が割れているときは、子のモジュール `経路の途中の試験` が確かめる。

use super::抽出の試験の段取り::原文から設計関係グラフと抽出の欠けを組む;
use blitz_design_verification::{原子命題, 命題, 命題の検証器, 未決定の理由, 検証結果, 構造の検証器, 設計概念への参照, 設計関係の種類, 項};

#[path = "定義をたどれない型への問いの試験/経路の途中の試験.rs"]
mod 経路の途中の試験;

const 定義のパス: &str = "crates/blitz_esca/src/旅行者.rs";
const 使う側のパス: &str = "crates/blitz_esca/src/使う側.rs";

// 定義のファイルと使う側のファイルを抽出して欠落を写し、原子命題1つを構造の検証器へ問う。
fn 抽出して問う(定義の原文: &str, 使う側の原文: &str, 原子: 原子命題) -> 検証結果 {
    let 抽出したもの = 原文から設計関係グラフと抽出の欠けを組む(&[(定義のパス, 定義の原文), (使う側のパス, 使う側の原文)]);
    構造の検証器::生成する(&抽出したもの.グラフ, 抽出したもの.関係を落とした抽出の欠落へ写す()).検証する(&命題::原子から組む(原子))
}

fn 未解決による未決定か(結果: &検証結果) -> bool {
    matches!(結果, 検証結果::未決定(未決定の理由::型の定義のモジュールパスが未解決である(_)))
}

fn 定義の型(名前: &str) -> 項 {
    項::名指した概念(設計概念への参照::型として生成する("blitz_esca::旅行者", 名前))
}

const 規則の定義: &str = "pub struct 歩行の規則 {\n    速さ: f32,\n}\n";
const 状態と遷移の宣言: &str = "pub struct 旅行者の現在地 {\n    東: f32,\n}\n\nimpl 旅行者の現在地 {}\n\nconst _: M規則で決まる遷移関数<旅行者の現在地, 歩行の規則> = M規則で決まる遷移関数::生成する(旅行者の現在地::動かす);\n";

// 遷移の宣言が包んだ処理が、定義のファイルの `歩行の規則` を参照するかの原子命題。
fn 処理が規則を参照する() -> 原子命題 {
    原子命題::設計関係が在る {
        主語: 項::名指した概念(設計概念への参照::処理として生成する("blitz_esca::使う側", "動かす").所有者を添える(vec!["旅行者の現在地".to_string()])),
        種類: 設計関係の種類::参照する,
        目的語: 定義の型("歩行の規則"),
    }
}

#[test]
fn 頭の端点の表記から型をたどれれば参照するが証明される() {
    let 使う側 = format!("use crate::旅行者::歩行の規則;\n\n{状態と遷移の宣言}");
    let 結果 = 抽出して問う(規則の定義, &使う側, 処理が規則を参照する());
    assert!(結果.証明済みか(), "{}", 結果.表記());
}

// 反証: 止めが無いと、関係は空の `歩行の規則` を目的語にして入り、定義の型への問いは辺の不在から反証される。
#[test]
fn 頭の端点の表記から型をたどれないとき参照するの問いは反証されず未決定になる() {
    let 結果 = 抽出して問う(規則の定義, 状態と遷移の宣言, 処理が規則を参照する());
    assert!(未解決による未決定か(&結果), "{}", 結果.表記());
}

// 定義のファイルの `旅行者の現在地` が `M状態` を分類に持つかの原子命題。
fn 定義の型が状態のマーカーを持つ() -> 原子命題 {
    原子命題::マーカーを持つ {
        概念: 定義の型("旅行者の現在地"),
        マーカー名: "M状態".to_string(),
    }
}

