const エンティティの定義: &str = "pub struct 旅行者ID {\n    値: u64,\n}\n\npub struct 旅行者 {\n    識別子: 旅行者ID,\n}\n";
const エンティティの実装: &str = "impl Mエンティティ for 旅行者 {\n    type 識別子 = 旅行者ID;\n}\n";

// 定義のファイルの `旅行者ID` が定義のファイルの `旅行者` を識別するかの原子命題。
fn 識別子がエンティティを識別する() -> 原子命題 {
    原子命題::設計関係が在る {
        主語: 定義の型("旅行者ID"),
        種類: 設計関係の種類::識別する,
        目的語: 定義の型("旅行者"),
    }
}

