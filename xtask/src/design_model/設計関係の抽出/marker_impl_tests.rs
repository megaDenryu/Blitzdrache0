//! 抽出の規則2(設計解釈マーカーの実装)の回帰試験。「このRustの構文からこの分類の事実が出て、設計関係は出ない」と、
//! 実装の対象の型の定義をたどれない実装が分類の答えを弱めることを固定する。

use super::test_support::{分類の事実の表記一覧, 原文から設計関係グラフと抽出の欠けを組む, 関係の表記一覧};
use blitz_design_verification::{原子命題, 命題, 命題の検証器, 未決定の理由, 検証結果, 構造の検証器, 設計概念への参照, 項};

#[test]
fn マーカーの実装から実装の事実が出て設計関係は出ない() {
    let 原文 = "pub struct 旅行者の現在地 {\n    東: f32,\n}\n\nimpl M状態 for 旅行者の現在地 {}\n";
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[("crates/blitz_esca/src/旅行者.rs", 原文)]);
    let 表記一覧 = 分類の事実の表記一覧(&結果);
    assert!(表記一覧.contains(&"blitz_esca::旅行者::旅行者の現在地 は blitz_design::設計解釈マーカー::M状態 を実装する".to_string()), "{表記一覧:?}");
    assert!(!関係の表記一覧(&結果).iter().any(|表記| 表記.contains("M状態")), "マーカーの実装から設計関係が出ている: {:?}", 関係の表記一覧(&結果));
}

#[test]
fn 修飾を書いたマーカーの実装からも同じ節点への事実が出る() {
    let 原文 = "pub struct 移動の変位 {\n    東: f32,\n}\n\nimpl blitz_design::M不変データ for 移動の変位 {}\n";
    let 表記一覧 = 分類の事実の表記一覧(&原文から設計関係グラフと抽出の欠けを組む(&[("crates/blitz_esca/src/旅行者.rs", 原文)]));
    assert!(表記一覧.contains(&"blitz_esca::旅行者::移動の変位 は blitz_design::設計解釈マーカー::M不変データ を実装する".to_string()), "{表記一覧:?}");
}

#[test]
fn 標準resultへの包括の実装は標準の型の節点として事実が出る() {
    let 原文 = "impl<T, E> M結果 for std::result::Result<T, E> {}\n";
    let 表記一覧 = 分類の事実の表記一覧(&原文から設計関係グラフと抽出の欠けを組む(&[("crates/blitz_design/src/設計解釈マーカー.rs", 原文)]));
    assert_eq!(表記一覧, vec!["std::result::Result は blitz_design::設計解釈マーカー::M結果 を実装する".to_string()]);
}

const 定義のパス: &str = "crates/blitz_esca/src/旅行者.rs";
const 実装のパス: &str = "crates/blitz_esca/src/分類.rs";
const 定義の原文: &str = "pub struct 旅行者の現在地 {\n    東: f32,\n}\n";

// 2つの原文を抽出して欠落を写し、定義の型の節点が `M状態` を分類に持つかを構造の検証器へ問う。
fn 定義の型が状態のマーカーを持つかを問う(実装の原文: &str) -> 検証結果 {
    let 抽出したもの = 原文から設計関係グラフと抽出の欠けを組む(&[(定義のパス, 定義の原文), (実装のパス, 実装の原文)]);
    let 問い = 命題::原子から組む(原子命題::マーカーを持つ {
        概念: 項::名指した概念(設計概念への参照::型として生成する("blitz_esca::旅行者", "旅行者の現在地")),
        マーカー名: "M状態".to_string(),
    });
    構造の検証器::生成する(&抽出したもの.グラフ, 抽出したもの.関係を落とした抽出の欠落へ写す()).検証する(&問い)
}

// 対照: 実装のファイルが型を取り込めば、分類の事実が定義の型の節点に付いて証明済みになる。
#[test]
fn 実装の対象の型の定義をたどれれば定義の型の分類が証明される() {
    let 結果 = 定義の型が状態のマーカーを持つかを問う("use crate::旅行者::旅行者の現在地;\n\nimpl M状態 for 旅行者の現在地 {}\n");
    assert!(結果.証明済みか(), "{}", 結果.表記());
}

// 反証: たどれなかった実装の行を識別子だけの未解決に数えると、分類の事実が空の節点にだけ付き、定義の型の節点の分類が不在から反証される。
#[test]
fn 実装の対象の型の定義をたどれないとき定義の型の分類の問いは反証されず未決定になる() {
    let 結果 = 定義の型が状態のマーカーを持つかを問う("impl M状態 for 旅行者の現在地 {}\n");
    assert!(matches!(結果, 検証結果::未決定(未決定の理由::関係を落とした抽出の欠落が在る(_))), "{}", 結果.表記());
}
