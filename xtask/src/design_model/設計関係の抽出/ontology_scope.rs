//! 設計オントロジーの適用範囲。どのクレートのソースを設計関係グラフの節点の供給元にするかを、クレート名の一覧で決める。
//!
//! 範囲をクレート名で持つのは、設計解釈マーカーを実装する型だけを節点にすると、マーカーを1つも実装しない中間の型で経路が切れ、
//! 「関係が無い」という偽の反証が出るためである(`crates/blitz_esca/src/walking_direction.rs` の `歩行方向` は `旅行者の意図` のフィールドだがマーカーを実装していない)。
//! 初版は `blitz_design` と `blitz_esca` の2つであった。この2つが設計解釈マーカーの正本とその最初の利用者であり、
//! 最初の実証範囲を定義元と最初の利用者に閉じるためである。2026-09-25に、アプリが実際に動かすゲームのロジック層である
//! `blitz_game` を足した(Issue #137・#175)。アプリから到達するかを問う検査は、アプリが呼ぶゲームの型が範囲に居なければ意味を持たないためである。
//! 他のクレートにもマーカーの実装は在る。範囲を広げるときはこの定数へクレート名を足す。
//!
//! 適用範囲は、設計語彙のクレート(設計解釈マーカーと関数の役割の正本を定義する `blitz_design`)と、その語彙を使うドメインのクレートの2つに分かれる。
//! 設計語彙のクレートの名前を持つのはこのファイルだけであり、マーカーの正本のモジュールパスもこの名前から組む。
//!
//! 騒がしさをこの段で潰さない。抽出の段で落とした情報は後段で復元できないが、後段の絞り込みは命題ごとに変えられる。

use std::path::Path;

use crate::conform::design_ontology::line_matching::クレート名;

/// 設計解釈マーカーと関数の役割の正本を定義する、設計語彙のクレートの名前。
pub const 設計語彙のクレート: &str = "blitz_design";

/// 設計オントロジーを適用するクレートの名前。先頭が設計語彙のクレートであり、残りがドメインのクレートである。
const 設計オントロジーの適用範囲: [&str; 3] = [設計語彙のクレート, "blitz_esca", "blitz_game"];

/// そのパスが設計オントロジーの適用範囲のクレートに属するか。
pub fn 適用範囲のクレートのパスか(パス: &Path) -> bool {
    設計オントロジーの適用範囲.iter().any(|名前| クレート名(パス) == *名前)
}

/// 適用範囲から設計語彙のクレートを除いた、設計語彙を使うドメインのクレートの名前の一覧。並びは適用範囲の並びのままである。
pub fn ドメインのクレートの名前一覧() -> impl Iterator<Item = &'static str> {
    設計オントロジーの適用範囲.into_iter().filter(|名前| *名前 != 設計語彙のクレート)
}

/// その名前がドメインのクレートの名前か。
pub fn ドメインのクレートか(名前: &str) -> bool {
    ドメインのクレートの名前一覧().any(|ドメインのクレート| ドメインのクレート == 名前)
}

#[cfg(test)]
mod tests {
    use super::{ドメインのクレートか, ドメインのクレートの名前一覧, 設計オントロジーの適用範囲, 設計語彙のクレート};

    #[test]
    fn ドメインのクレートは適用範囲から設計語彙のクレートだけを除いたものである() {
        let 一覧: Vec<&str> = ドメインのクレートの名前一覧().collect();
        assert_eq!(一覧.len(), 設計オントロジーの適用範囲.len() - 1, "設計語彙のクレートは適用範囲にちょうど1回だけ現れる");
        assert!(一覧.iter().all(|名前| 設計オントロジーの適用範囲.contains(名前)), "ドメインのクレートは適用範囲の外から来ない");
        assert!(!ドメインのクレートか(設計語彙のクレート));
        assert!(一覧.iter().all(|名前| ドメインのクレートか(名前)));
        assert!(!ドメインのクレートか("blitz_sim"), "適用範囲の外のクレートはドメインのクレートでない");
    }
}
