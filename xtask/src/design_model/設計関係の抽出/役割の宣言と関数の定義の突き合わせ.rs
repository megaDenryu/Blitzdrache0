//! 役割の宣言と関数の定義の突き合わせ。受け取るのは全ての規則の成果を併せた抽出の成果、返すのは、関数の役割の宣言の処理を、その関数の署名の事実の処理(関数を定義した位置で組んだ識別子)へ揃えた成果である。
//!
//! 役割の宣言の事実は、処理の識別子を使用箇所のファイルのモジュールパスで組む。関数の署名の事実は、`fn` を書いた位置のモジュール(波括弧付きの `mod` を含む)で組む。
//! 関数を別のファイルの `impl` や波括弧付きの `mod` の中に置くと2つが食い違い、同じ関数が2つの処理の節点へ割れて、役割が導く設計関係と署名が導く関係が別の節点に付く。
//! 関数の定義の位置を正とするのは、使用箇所がどこであっても関数そのものは1つだからである。
//!
//! 突き合わせる候補は、同じクレートの署名の事実のうち、所有者の並びと関数の名前が役割の宣言と同じものである。固有の実装はその型を定義したクレートにしか書けないため、
//! 候補を同じクレートに限ってよい。候補が1つなら揃え、2つ以上なら決められないため役割の宣言を抽出できなかった行に数えて事実を落とす(黙って1つを選ばない)。
//! 候補が無いときは使用箇所で組んだ識別子のまま残す。関数の見出しを読めなかった行は署名の抽出が既に数えており、マクロが作る関数のように見出しがソースに無い関数もあるためである。

use super::抽出できなかった行の定義::{抽出できなかった理由, 抽出できなかった行};
use super::抽出の成果と欠け::抽出の成果;
use blitz_design_verification::{設計概念, 関数の役割の宣言の事実};

impl 抽出の成果 {
    /// 関数の役割の宣言の処理を、同じ関数の署名の事実の処理へ揃えた成果。
    pub fn 役割の宣言の処理を関数の定義へ揃える(mut self) -> Self {
        let 宣言一覧 = std::mem::take(&mut self.事実.関数の役割の宣言一覧);
        for 宣言 in 宣言一覧 {
            let 候補一覧 = self.同じ関数の署名の処理一覧(&宣言.処理);
            match 候補一覧.as_slice() {
                [] => self.事実.関数の役割の宣言一覧.push(宣言),
                [定義の処理] => {
                    let 処理 = 定義の処理.clone();
                    self.事実.関数の役割の宣言一覧.push(関数の役割の宣言の事実 { 処理, ..宣言 });
                }
                _ => {
                    let 理由 = 抽出できなかった理由::役割に包まれた関数の定義が一意に決まらない {
                        役割名: 宣言.役割.名前(),
                        関数名: 宣言.処理.識別子().表記(),
                        候補の数: 候補一覧.len(),
                    };
                    self.抽出できなかった行一覧.push(抽出できなかった行::生成する(&宣言.出どころ.パス, 宣言.出どころ.行番号, 理由));
                }
            }
        }
        self
    }

    // 役割の宣言の処理と、クレート名・所有者の並び・名前が同じ署名の事実の処理の一覧。同じ処理が2度並ばない。
    fn 同じ関数の署名の処理一覧(&self, 宣言の処理: &設計概念) -> Vec<設計概念> {
        let 識別子 = 宣言の処理.識別子();
        let mut 一覧: Vec<設計概念> = Vec::new();
        for 署名 in &self.事実.関数の署名一覧 {
            let 候補 = 署名.処理.識別子();
            if 候補.クレート名() == 識別子.クレート名() && 候補.所有者の並び == 識別子.所有者の並び && 候補.名前 == 識別子.名前 && !一覧.contains(&署名.処理) {
                一覧.push(署名.処理.clone());
            }
        }
        一覧
    }
}
