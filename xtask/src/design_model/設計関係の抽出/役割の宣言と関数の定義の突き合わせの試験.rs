//! 関数の役割の宣言の処理が、関数を定義した位置で組んだ関数の署名の事実の処理へ揃うことを固定する回帰試験。
//! 揃わないと、同じ関数が2つの処理の節点へ割れ、役割が導く設計関係と署名が導く関係が別の節点に付く。

use super::抽出の成果と欠け::抽出した設計関係グラフと抽出の欠け;
use super::抽出の試験の段取り::{原文から設計関係グラフと抽出の欠けを組む, 抽出できなかった理由の説明一覧};
use crate::design_model::設計概念の種類;

const 使用箇所のパス: &str = "crates/blitz_esca/src/旅行者.rs";
const 使用箇所: &str = "pub struct 入力 {\n    前: bool,\n}\n\npub enum 意図 {\n    静止,\n}\n\nimpl 入力 {}\n\nconst _: M解釈関数<入力, 意図> = M解釈関数::生成する(入力::解釈する);\n";
const 実装: &str = "impl 入力 {\n    pub fn 解釈する(&self) -> 意図 {\n        todo!()\n    }\n}\n";

// 処理の節点の数と、役割の宣言の処理の表記。
fn 処理の節点の数と宣言の処理(結果: &抽出した設計関係グラフと抽出の欠け) -> (usize, String) {
    let 数 = 結果.グラフ.概念一覧().iter().filter(|概念| 概念.種類() == 設計概念の種類::処理).count();
    (数, 結果.事実.関数の役割の宣言一覧[0].処理.識別子().表記())
}

// 反証: 役割の宣言の処理を使用箇所のファイルで組んだままにすると、波括弧付きの `mod` の中の関数と2つの節点へ割れる。
#[test]
fn 波括弧付きのモジュールの中の関数へ役割の宣言の処理が揃う() {
    let 原文 = format!("{使用箇所}\nmod 内側 {{\n    use super::{{入力, 意図}};\n\n    {}}}\n", 実装.replace('\n', "\n    "));
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[(使用箇所のパス, &原文)]);
    assert_eq!(処理の節点の数と宣言の処理(&結果), (1, "blitz_esca::旅行者::内側::入力::解釈する".to_string()));
}

// 反証: 役割の宣言の処理を使用箇所のファイルで組んだままにすると、別のファイルの `impl` の関数と2つの節点へ割れる。
#[test]
fn 別のファイルの実装の関数へ役割の宣言の処理が揃う() {
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[(使用箇所のパス, 使用箇所), ("crates/blitz_esca/src/入力の実装.rs", 実装)]);
    assert_eq!(処理の節点の数と宣言の処理(&結果), (1, "blitz_esca::入力の実装::入力::解釈する".to_string()));
}

// 同じクレートに所有者と名前が同じ関数の定義が2つ在ると、黙って1つを選ばず、役割の宣言を抽出できなかった行に数える。
#[test]
fn 関数の定義が一意に決まらなければ役割の宣言を落として数える() {
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[(使用箇所のパス, 使用箇所), ("crates/blitz_esca/src/甲.rs", 実装), ("crates/blitz_esca/src/乙.rs", 実装)]);
    assert!(結果.事実.関数の役割の宣言一覧.is_empty(), "{:?}", 結果.事実.関数の役割の宣言一覧);
    assert!(抽出できなかった理由の説明一覧(&結果).iter().any(|説明| 説明.contains("同じクレートに2個在り")), "{:?}", 抽出できなかった理由の説明一覧(&結果));
}
