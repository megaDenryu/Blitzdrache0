//! 関数を持つ位置の走査。ファイルの行を頭から読み、開いている波括弧が何の本体かを数えて、いまの行が関数の項目を書ける位置(項目の位置)かと、
//! そこに書いた関数を誰が持つかを答える。受け取るのはファイルのモジュールパスと、行ごとのコードだけの行、返すのは関数を書いた場所か、項目の位置でないという答えである。
//!
//! 項目の位置とは、モジュールの直下(波括弧付きのモジュール `mod 名 { … }` の本体を含む)と、`impl … { }` と `trait … { }` の本体の直下のことである。
//! 関数・構造体・マクロなどの本体の波括弧が1つでも内側に開いていれば、その行は項目の位置でない。抽出器はその位置の `fn` を項目として読まない。
//! 見出しの中で本体より前に開く波括弧(型引数の定数式)は、本体の波括弧と取り違えないよう数えて読み飛ばす。
//! 走査の状態(開いている波括弧の並びと、次に開く本体)をこの型が所有するのは、行ごとの呼び出しに同じ状態を持参させないためである。

#[path = "関数を持つ位置/項目の見出しの読み取り.rs"]
mod 項目の見出しの読み取り;

use crate::conform::design_ontology::module_path::モジュールパス;
use blitz_design_verification::関数の所有者;
use 項目の見出しの読み取り::見出しから次に開く本体を読む;

/// 関数を書いた場所とは、項目の位置の関数を囲む実装かトレイトの本体(所有者)と、処理の識別子へ添える所有者の名前の並びと、そこで有効な型引数の名前と、位置のモジュールの組である。
pub struct 関数を書いた場所 {
    pub 所有者の名前一覧: Vec<String>, // 処理の識別子の所有者の並び。自由関数では空、トレイトの実装では対象の型の名前とトレイトの表記の2つである
    pub 所有者: 関数の所有者,
    pub 型引数名一覧: Vec<String>,
    pub モジュールパス: モジュールパス,
}

/// 開いている波括弧1つが何の本体か。
enum 開いた波括弧 {
    モジュールの本体(String),
    実装かトレイトの本体 {
        所有者の名前一覧: Vec<String>,
        所有者: 関数の所有者,
        型引数名一覧: Vec<String>,
    },
    その他の本体,
}

/// 見出しを読んだ項目が、次に開く波括弧で開く本体。見出しの中で本体より前に開く波括弧の数を持つ。
struct 次に開く本体 {
    読み飛ばす波括弧の数: usize,
    本体: 開いた波括弧,
}

/// 1つのファイルの行を頭から読む走査。
pub struct 関数を持つ位置の走査 {
    ファイルのモジュールパス: モジュールパス,
    開いた一覧: Vec<開いた波括弧>,
    次に開く本体: Option<次に開く本体>,
}

impl 関数を持つ位置の走査 {
    pub fn 生成する(ファイルのモジュールパス: モジュールパス) -> Self {
        Self {
            ファイルのモジュールパス,
            開いた一覧: Vec::new(),
            次に開く本体: None,
        }
    }

    /// いまの行が項目の位置なら、そこに書いた関数を書いた場所。項目の位置でなければ無しである。
    pub fn いまの関数を書いた場所(&self) -> Option<関数を書いた場所> {
        let モジュールパス = self.位置のモジュール();
        match self.開いた一覧.last() {
            None | Some(開いた波括弧::モジュールの本体(_)) => Some(関数を書いた場所 {
                所有者の名前一覧: Vec::new(),
                所有者: 関数の所有者::自由関数,
                型引数名一覧: Vec::new(),
                モジュールパス,
            }),
            Some(開いた波括弧::実装かトレイトの本体 {
                所有者の名前一覧, 所有者, 型引数名一覧
            }) => Some(関数を書いた場所 {
                所有者の名前一覧: 所有者の名前一覧.clone(),
                所有者: 所有者.clone(),
                型引数名一覧: 型引数名一覧.clone(),
                モジュールパス,
            }),
            Some(開いた波括弧::その他の本体) => None,
        }
    }

    /// その行を読み、項目の位置の見出しなら次に開く本体を覚え、行の波括弧で本体を開いて閉じる。
    pub fn 行を読む(&mut self, 行一覧: &[String], 添字: usize) {
        if self.次に開く本体.is_none() && !matches!(self.開いた一覧.last(), Some(開いた波括弧::その他の本体)) {
            self.次に開く本体 = 見出しから次に開く本体を読む(行一覧, 添字, &self.位置のモジュール());
        }
        for 文字 in 行一覧[添字].chars() {
            match 文字 {
                '{' => {
                    let 本体 = self.次の波括弧の本体();
                    self.開いた一覧.push(本体);
                }
                '}' => {
                    self.開いた一覧.pop();
                }
                _ => {}
            }
        }
    }

    // 次に開く波括弧の本体。覚えた本体が無いか、見出しの中の波括弧を読み飛ばしている間は、その他の本体である。
    fn 次の波括弧の本体(&mut self) -> 開いた波括弧 {
        match self.次に開く本体.take() {
            Some(次) if 次.読み飛ばす波括弧の数 > 0 => {
                self.次に開く本体 = Some(次に開く本体 {
                    読み飛ばす波括弧の数: 次.読み飛ばす波括弧の数 - 1,
                    ..次
                });
                開いた波括弧::その他の本体
            }
            Some(次) => 次.本体,
            None => 開いた波括弧::その他の本体,
        }
    }

    // ファイルのモジュールパスの下へ、開いている波括弧付きのモジュールの名前を外側から繋いだ位置のモジュール。
    fn 位置のモジュール(&self) -> モジュールパス {
        let 名前一覧: Vec<&str> = self.開いた一覧.iter().filter_map(|波括弧| if let 開いた波括弧::モジュールの本体(名前) = 波括弧 { Some(名前.as_str()) } else { None }).collect();
        self.ファイルのモジュールパス.下へ繋ぐ(&名前一覧)
    }
}
