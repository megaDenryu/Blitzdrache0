//! 抽出できなかった行を検証器へ渡す欠落へ写すとき、行ごとに弱める答えが絞られることを固定する試験。
//! 定義の式の規則の本体で読めなかった行はその規則の頭の関係の答えだけを、ソースの構文を読めなかった行はその事実を本体で読む規則の答えを弱める。

use std::path::PathBuf;

use super::super::test_support::原文から設計関係グラフと抽出の欠けを組む;
use super::super::抽出できなかった行の定義::抽出できなかった行;
use super::抽出した設計関係グラフと抽出の欠け;
use blitz_design_verification::{事実の出どころ, 型の表記を読めない理由, 導出の欠け, 導出の欠けの理由, 欠落が弱める答え, 設計関係の種類, 頭の関係};

const 識別する: 欠落が弱める答え = 欠落が弱める答え::設計関係(設計関係の種類::識別する);
const 消費する: 欠落が弱める答え = 欠落が弱める答え::設計関係(設計関係の種類::消費する);

#[test]
fn 保持するの規則で型の表記を読めない行は保持するの答えだけを弱める() {
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[("crates/blitz_game/src/描画の材料.rs", "pub struct 描画の材料 {\n    形: Handle<メッシュ>,\n}\n")]);
    let 欠落 = 結果.関係を落とした抽出の欠落へ写す();
    assert!(欠落.どれかの答えを弱めるか(&[欠落が弱める答え::保持する関係]), "{}", 欠落.説明());
    assert!(!欠落.どれかの答えを弱めるか(&[識別する, 消費する, 欠落が弱める答え::分類]), "{}", 欠落.説明());
}

#[test]
fn 読めない型定義の宣言はフィールドを読む規則の答えを弱め識別するの答えを弱めない() {
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[("crates/blitz_esca/src/旅行者.rs", "pub struct 旅行者\n{\n    現在地: 旅行者の現在地,\n}\n")]);
    let 欠落 = 結果.関係を落とした抽出の欠落へ写す();
    assert!(欠落.どれかの答えを弱めるか(&[欠落が弱める答え::保持する関係]), "{}", 欠落.説明());
    assert!(欠落.どれかの答えを弱めるか(&[消費する]), "命令の組を通した消費の規則もフィールドを読む: {}", 欠落.説明());
    assert!(!欠落.どれかの答えを弱めるか(&[識別する, 欠落が弱める答え::分類]), "{}", 欠落.説明());
}

#[test]
fn 読めないトレイトの宣言は分類と分類を読む規則の答えを弱め保持するの答えを弱めない() {
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[("crates/blitz_esca/src/ontology.rs", "pub trait M旅程: M状態 where Self: Sized {}\n")]);
    let 欠落 = 結果.関係を落とした抽出の欠落へ写す();
    assert!(欠落.どれかの答えを弱めるか(&[欠落が弱める答え::分類]), "{}", 欠落.説明());
    assert!(欠落.どれかの答えを弱めるか(&[消費する]), "命令の組を通した消費の規則は分類を読む: {}", 欠落.説明());
    assert!(!欠落.どれかの答えを弱めるか(&[欠落が弱める答え::保持する関係, 識別する]), "{}", 欠落.説明());
}

// 導けなかった関係を頭に持つ規則で、パスの修飾がある型の表記を読めなかった導出の欠け1件から組んだ行。
fn 修飾のある表記を読めなかった行(導けなかった関係: 頭の関係, 行番号: usize) -> 抽出できなかった行 {
    抽出できなかった行::導出の欠けから生成する(導出の欠け {
        出どころ: 事実の出どころ {
            パス: PathBuf::from("crates/blitz_esca/src/旅行者.rs"),
            行番号,
        },
        理由: 導出の欠けの理由::型の表記を読めない(型の表記を読めない理由::型の表記にパスの修飾がある {
            表記: "crate::旅行者の現在地".to_string()
        }),
        導けなかった関係,
    })
}

// 反証: 呼び名だけでまとめると、保持するの答えの未決定の理由に、消費するの規則で読めなかった行まで数える。
#[test]
fn 同じ呼び名でも弱める答えが違う行は別の件に数える() {
    let 抽出したもの = 抽出した設計関係グラフと抽出の欠け {
        抽出できなかった行一覧: vec![
            修飾のある表記を読めなかった行(頭の関係::保持する, 2),
            修飾のある表記を読めなかった行(頭の関係::保持する, 3),
            修飾のある表記を読めなかった行(頭の関係::設計関係(設計関係の種類::消費する), 4),
        ],
        ..抽出した設計関係グラフと抽出の欠け::default()
    };
    let 欠落 = 抽出したもの.関係を落とした抽出の欠落へ写す();
    let 保持するの説明 = 欠落.答えを弱める件の説明(&[欠落が弱める答え::保持する関係]);
    assert!(保持するの説明.contains("型の表記にパスの修飾がある: 2件"), "{保持するの説明}");
    let 消費するの説明 = 欠落.答えを弱める件の説明(&[消費する]);
    assert!(消費するの説明.contains("型の表記にパスの修飾がある: 1件"), "{消費するの説明}");
    assert_eq!(欠落.合計の件数(), 3);
}
