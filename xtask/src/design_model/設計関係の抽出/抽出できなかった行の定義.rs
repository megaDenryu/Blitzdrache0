//! 抽出できなかった行とは、抽出の規則が当たる構文でありながら、抽出器がそこから設計関係を1件も組めなかったソースの行のことである。
//!
//! この型が在るのは、検査器が解析できなかった入力を黙って対象から外してはならないという規約のためである
//! (`.claude/global-reference/全プロジェクト共通CLAUDE.md`「検査器は解析できなかった入力を黙って対象から外してはならない」)。
//! 抽出の結果はこの一覧を件数として持ち、命題の検証の利用者が「関係が0件である」と「その行を読めなかった」を読み分けられるようにする。
//!
//! 黙って対象から外してよいのは、外す条件を書き下せる入力だけである。抽出器がそれとして扱うのは2つだけであり、
//! 設計の概念でないプリミティブの型(`u32`・`String` 等)と、役割の型自身の実装の行である。どちらも理由の選択肢を持たない。
//! Graphiteの生成物を取り込む `mod` も外す条件を書き下せる入力であるが、件数を見せるため理由の選択肢を持たせて数える。
//! 規則が当たる位置に在りながら抽出器が構文を読めない文字列は、`保証範囲の外の構文` が名指して欠落へ倒す。黙って読み飛ばさない。
//!
//! **理由は4つの区分のどれかへ属する。** 区分とその答え方は `抽出できなかった理由の区分` が持つ。
//! 行は、ソースの構文を読めなかったのか、定義の式の規則の本体で導けなかったのかも持つ。後者は同じ理由(型の表記を読めない)でも、
//! 欠けた規則の頭の関係だけが失われており、ソースの構文から区分が答える事実と違うためである。

#[path = "抽出できなかった行の定義/抽出できなかった理由の説明.rs"]
mod 抽出できなかった理由の説明;

use std::path::{Path, PathBuf};

use blitz_design_verification::{名指せなかった変数の位置, 型の表記を読めない理由, 導出の欠け, 導出の欠けの理由, 頭の関係};

use super::保証範囲の外の構文の定義::保証範囲の外の構文;
use super::関数の見出しの読み取り::関数の見出しを読めない理由;

/// 抽出できなかった行の1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 抽出できなかった行 {
    pub パス: PathBuf,
    pub 行番号: usize, // 1始まり
    pub 理由: 抽出できなかった理由,
    pub 読めなかった箇所: 読めなかった箇所,
}

/// その行で読めなかったのが、ソースの構文か、定義の式の規則の本体か。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 読めなかった箇所 {
    /// 抽出の規則がソースの構文を読めなかった。読めなかった事実は理由の区分が答える。
    ソースの構文,
    /// 定義の式の評価器が、その頭の関係を導く規則の本体で型の表記を読めなかった。
    定義の式の規則の本体 { 導けなかった関係: 頭の関係 },
}

/// 抽出器がその行から設計関係を組めなかった理由。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 抽出できなかった理由 {
    /// フィールドの型が、その定義の宣言が導入した型引数の名前である。実在しない設計概念の節点を作らないために関係を出さない。
    型引数である { 型引数名: String },
    /// 型の定義をたどれず、節点のモジュールパスを空にした。節点そのものは落とさない。
    定義のモジュールパスを解決できなかった { 型名: String },
    /// 定義の式の規則の本体の途中の変数(頭に現れない経由する概念か、分類を問われる変数)へ名指した型の定義をたどれず、空の節点では本体が成り立たずに頭の関係ごと落ちた。
    規則の本体の途中で名指した型の定義をたどれなかった { 型名: String, 導けなかった関係: 頭の関係 },
    /// 役割の型引数の数が、その役割が取る数と合わない。
    役割の型引数の数が合わない { 役割名: &'static str, 取る数: usize, 読めた数: usize },
    /// 役割の値の右辺が `<役割名>::生成する(...)` の形でなく、関係の主語を決められない(戻り値の型・フィールドの型注釈・`= 何か.何か()` の形)。
    役割の値の右辺が役割の生成する呼び出しでない { 役割名: &'static str },
    /// 役割の `生成する` へ渡した引数がRustのパスとして読めず、関係の主語を決められない。
    役割に包まれた関数の引数がパスでない { 役割名: &'static str },
    /// 役割に包まれた関数のパスを `::` で分けた区分が、所有する型1つとメソッド1つの2つでない。
    役割に包まれた関数のパスの区分が2つでない { 役割名: &'static str, 読めた区分の数: usize },
    /// 役割に包まれた関数のパスの1つ目の区分が `crate`・`self`・`super` のどれかであり、所有する型の名前でない。
    役割に包まれた関数のパスが起点の予約語で始まる { 役割名: &'static str, 先頭の区分: String },
    /// 役割に包まれた関数の所有者を対象にする `impl` の行が同じファイルに無く、所有者のモジュールパスを当てる根拠が無い。
    役割に包まれた関数の所有者の実装が同じファイルに無い { 役割名: &'static str, 所有者名: String },
    /// 項目の位置(モジュールの直下と `impl`・`trait` の本体の直下)でない場所に書いた `fn` であり、抽出器が項目として読まない。
    項目の位置でない関数である { 関数名: String },
    /// 定義の式の署名の読み方が、関数の署名の型の表記を読めない(関数ポインタ・クロージャ・関連型など)。
    関数の署名の型の表記を読めない { 理由: 型の表記を読めない理由 },
    /// 関数の署名の型の表記が、それを書いた場所で有効な型引数の名前であり、関数が扱う型を名指せない。
    関数の署名の型引数である { 型引数名: String },
    /// 行の頭でない位置に `fn` の見出しがあり(1行に書いた本体など)、抽出器が見出しとして読まない。
    関数の見出しが行の頭に無い { 関数名: String },
    /// 項目の位置の `fn` の見出しを読めず、関数の署名の事実を組めない。
    関数の見出しを読めない { 理由: 関数の見出しを読めない理由 },
    /// `impl Mエンティティ for 型` の本体に `type 識別子 =` の行が無く、識別する関係の主語を決められない。
    エンティティの識別子の関連型が無い { 型名: String },
    /// 関数の役割の型自身の宣言である。包んでいるのは関数ポインタであり、規則5の事実から定義の式が別に関係を導く。
    役割の型自身の宣言である { 役割名: &'static str },
    /// 抽出の規則が当たる位置に在りながら、抽出器がその文字列を読めない。
    保証範囲の外の構文である { 構文: 保証範囲の外の構文 },
    /// Graphiteの生成物を取り込む波括弧付きのモジュールであり、取り込んだ本体を辿らない。生成物はGraphiteの固定の語彙であり、ドメインの設計ではない。
    Graphiteの生成物の取り込みである { モジュール名: String },
}

impl 抽出できなかった行 {
    /// ソースの構文を読めなかった1件を、パスと行番号と理由から組む。
    pub fn 生成する(パス: &Path, 行番号: usize, 理由: 抽出できなかった理由) -> Self {
        Self {
            パス: パス.to_path_buf(),
            行番号,
            理由,
            読めなかった箇所: 読めなかった箇所::ソースの構文,
        }
    }

    /// 定義の式の評価器が導けなかった箇所から1件を組む。4つの理由は、段階2(Issue #193)の前に抽出器が自分で数えていた理由へそのまま写り、
    /// 区分(関係そのものを落としたか)も同じになる。役割の型引数の数が合わない宣言は抽出器が事実にしないため、本番では評価器から届かない。
    /// 定義をたどれなかった型のうち、規則の本体の途中の変数へ名指したものだけは別の理由へ写す。頭の関係ごと落ちており、識別子だけの未解決と違うためである。
    /// 行は欠けた規則の頭の関係を持ち、欠落はその関係の答えだけを弱める。
    pub fn 導出の欠けから生成する(欠け: 導出の欠け) -> Self {
        let 理由 = match 欠け.理由 {
            導出の欠けの理由::役割の型引数の数が合わない { 役割, 読めた数, .. } => 抽出できなかった理由::役割の型引数の数が合わない {
                役割名: 役割.名前(),
                取る数: 役割.型引数の数(),
                読めた数,
            },
            導出の欠けの理由::型の表記を読めない(読めない理由) => 抽出できなかった理由::保証範囲の外の構文である {
                構文: 保証範囲の外の構文::型の表記を読めない(読めない理由),
            },
            導出の欠けの理由::型引数である { 型引数名 } => 抽出できなかった理由::型引数である { 型引数名 },
            導出の欠けの理由::関数の署名の型の表記を読めない(理由) => 抽出できなかった理由::関数の署名の型の表記を読めない { 理由 },
            導出の欠けの理由::関数の署名の型引数である { 型引数名 } => 抽出できなかった理由::関数の署名の型引数である { 型引数名 },
            導出の欠けの理由::定義のモジュールパスを解決できなかった {
                型名,
                変数の位置: 名指せなかった変数の位置::頭の端点,
            } => 抽出できなかった理由::定義のモジュールパスを解決できなかった { 型名 },
            導出の欠けの理由::定義のモジュールパスを解決できなかった {
                型名,
                変数の位置: 名指せなかった変数の位置::本体の途中,
            } => 抽出できなかった理由::規則の本体の途中で名指した型の定義をたどれなかった {
                型名, 導けなかった関係: 欠け.導けなかった関係
            },
        };
        Self {
            読めなかった箇所: 読めなかった箇所::定義の式の規則の本体 {
                導けなかった関係: 欠け.導けなかった関係
            },
            ..Self::生成する(&欠け.出どころ.パス, 欠け.出どころ.行番号, 理由)
        }
    }

    /// 人が読む1行の表記。報告がこの表記を並べる。
    pub fn 表記(&self) -> String {
        format!("{}:{}: {}", self.パス.display(), self.行番号, self.理由.説明())
    }
}

impl 抽出できなかった理由 {
    /// その理由が名指す保証範囲の外の構文。`cargo xtask conform` がこのメソッドから違反を組む。
    pub const fn 保証範囲の外の構文を採る(&self) -> Option<&保証範囲の外の構文> {
        if let Self::保証範囲の外の構文である { 構文 } = self { Some(構文) } else { None }
    }
}
