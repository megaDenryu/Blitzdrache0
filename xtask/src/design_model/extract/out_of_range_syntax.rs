//! 抽出器が受理しないRustの構文の数え上げ。抽出の規則が当たる位置に在りながら、抽出器の保証範囲の外である文字列を表す。
//!
//! この列挙が在るのは、保証範囲をモジュールの注釈で述べるだけでは、範囲の外の文字列が「関係も出ず欠落にも数えられない」第三の状態へ落ちるためである。
//! 範囲の外であることをここで名指しすると、抽出はその1件を `抽出できなかった行` として数え、`cargo xtask conform` は同じ列挙をそのまま違反として報告できる。
//! 2つの利用者が同じ語彙を読むため、抽出が受理する形と検査が強制する形が食い違わない。
//!
//! 保証範囲の判定そのものを持つのは構文を読む工程(`struct_declaration`・`declaration_body_line`・`trait_declaration`・`type_notation`)であり、この列挙はその答えの語彙だけを持つ。

/// 抽出器の保証範囲の外にあるRustの構文1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 保証範囲の外の構文 {
    /// 本番で有効かを判断できない条件付きコンパイルである。
    本番の条件付きコンパイルを判定できない,
    /// モジュールの本体を本番の別ファイルとして一意に辿れない。
    本番のモジュールを辿れない,
    /// `struct`・`enum` の宣言の行が、本体を開く `{` にも本体を持たない `;` にも届いていない。
    型定義の宣言が1行に収まっていない { 型名: String },
    /// `struct`・`enum` の宣言の型引数の中に入れ子の型引数があり、型引数の名前を読み分けられない。
    型定義の型引数に入れ子の型引数がある { 型名: String },
    /// 位置で並べた本体(タプル構造体・タプルの選択肢)の型を、括弧の深さで区切れない。
    位置で並べた本体の型を区切れない { 型名: String },
    /// 型定義の本体の行が、フィールドの記述でも属性でも選択肢の名前でもない。
    型定義の本体の行がフィールドの記述でない { 型名: String, 行の表記: String },
    /// 型の表記が、参照と包みを落とした後もRustのパスとして読めない(配列・タプル・関数ポインタ・`impl`・`dyn`・生ポインタ)。
    型の表記がRustのパスでない { 表記: String },
    /// 型の表記が、剥がしてよい包み(`Vec`・`Option`・`Box`)でないジェネリクスであり、内側の型への関係を表せない。
    型の表記が剥がす包みでないジェネリクスである { 表記: String },
    /// 型の表記にパスの修飾があり、修飾を落として名前で解決すると別の定義へ当たりうる。
    型の表記にパスの修飾がある { 表記: String },
    /// `trait` の宣言の行が、本体を開く `{` に届いていない。
    トレイトの宣言が1行に収まっていない { トレイト名: String },
    /// `trait` の宣言の型引数の中に入れ子の型引数があり、型引数の終わりを読み分けられない。
    トレイトの型引数に入れ子の型引数がある { トレイト名: String },
    /// `trait` の宣言が `where` 節を持ち、そこに書かれた上位トレイトを読めない。
    トレイトの宣言がwhere節を持つ { トレイト名: String },
}

impl 保証範囲の外の構文 {
    /// 選択肢の種別の呼び名。運ぶ値(型名・表記)を含めないのは、この呼び名が同じ種別を束ねた件数の見出しになるためである。
    pub const fn 種別の呼び名(&self) -> &'static str {
        match self {
            Self::本番の条件付きコンパイルを判定できない => "本番の条件付きコンパイルを判定できない",
            Self::本番のモジュールを辿れない => "本番のモジュールを辿れない",
            Self::型定義の宣言が1行に収まっていない { .. } => "型定義の宣言が1行に収まっていない",
            Self::型定義の型引数に入れ子の型引数がある { .. } => "型定義の型引数に入れ子の型引数がある",
            Self::位置で並べた本体の型を区切れない { .. } => "位置で並べた本体の型を区切れない",
            Self::型定義の本体の行がフィールドの記述でない { .. } => "型定義の本体の行がフィールドの記述でない",
            Self::型の表記がRustのパスでない { .. } => "型の表記がRustのパスでない",
            Self::型の表記が剥がす包みでないジェネリクスである { .. } => "型の表記が剥がす包みでないジェネリクスである",
            Self::型の表記にパスの修飾がある { .. } => "型の表記にパスの修飾がある",
            Self::トレイトの宣言が1行に収まっていない { .. } => "トレイトの宣言が1行に収まっていない",
            Self::トレイトの型引数に入れ子の型引数がある { .. } => "トレイトの型引数に入れ子の型引数がある",
            Self::トレイトの宣言がwhere節を持つ { .. } => "トレイトの宣言がwhere節を持つ",
        }
    }

    /// 人が読む説明。抽出できなかった行の一覧と `cargo xtask conform` の違反の両方がこの1文を出す。
    pub fn 説明(&self) -> String {
        match self {
            Self::本番の条件付きコンパイルを判定できない => "抽出器はcfg(test)とcfg(not(test))以外の条件を本番の事実として採用しない".to_string(),
            Self::本番のモジュールを辿れない => "抽出器は本番のモジュールの本体を一意な別ファイルとして辿れない".to_string(),
            Self::型定義の宣言が1行に収まっていない { 型名 } => format!("`{型名}` の宣言が1行に収まっておらず抽出器の保証範囲の外である"),
            Self::型定義の型引数に入れ子の型引数がある { 型名 } => format!("`{型名}` の型引数に入れ子の型引数があり抽出器の保証範囲の外である"),
            Self::位置で並べた本体の型を区切れない { 型名 } => format!("`{型名}` の位置で並べた本体の型を括弧の深さで区切れない"),
            Self::型定義の本体の行がフィールドの記述でない { 型名, 行の表記 } => format!("`{型名}` の本体の行 `{行の表記}` がフィールドの記述でも属性でも選択肢の名前でもない"),
            Self::型の表記がRustのパスでない { 表記 } => format!("型の表記 `{表記}` が参照と包みを落とした後もRustのパスとして読めない"),
            Self::型の表記が剥がす包みでないジェネリクスである { 表記 } => format!("型の表記 `{表記}` が `Vec`・`Option`・`Box` 以外のジェネリクスであり内側の型への関係を表せない"),
            Self::型の表記にパスの修飾がある { 表記 } => format!("型の表記 `{表記}` にパスの修飾があり、修飾を落として名前で解決すると別の定義へ当たりうる"),
            Self::トレイトの宣言が1行に収まっていない { トレイト名 } => format!("`{トレイト名}` のトレイトの宣言が1行に収まっておらず上位トレイトを読めない"),
            Self::トレイトの型引数に入れ子の型引数がある { トレイト名 } => format!("`{トレイト名}` のトレイトの型引数に入れ子の型引数があり上位トレイトを読み分けられない"),
            Self::トレイトの宣言がwhere節を持つ { トレイト名 } => format!("`{トレイト名}` のトレイトの宣言が `where` 節を持ち、そこに書かれた上位トレイトを読めない"),
        }
    }
}
