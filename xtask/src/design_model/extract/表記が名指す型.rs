//! 型の表記が名指す型と、座標系を型引数に取る `blitz_math` のフレーム型の一覧。依存を持たない純粋な値と関数だけを置く。
//! 受け取るのは型の表記を包みまで剥がした芯の名前と型引数の並び、返すのは節点の同一性の名前と定義を探す名前を答える値である。
//!
//! 剥がす包み(`Vec` 等)でない総称の型のうち、1つの型として受理するのはこの一覧に載ったフレーム型だけである。
//! 型引数の形(型の名前だけが並ぶ等)で受理を決めないのは、`Handle<メッシュ>` のように型引数の側が関係の相手である型にも当たり、
//! 内側の型への `保持する` を黙って捨てることになるためである。フレーム型の型引数は座標系を区別する幻影型であり、関係の相手にならない。
//! `変位<ワールド>` と `変位<ローカル>` はRust上で別の型であるため、同一性の名前には座標系を含める。定義は座標系を落とした名前で探す。
//! 一覧が `blitz_math` の実物と過不足なく一致することは、実物を走査する試験(`フレーム型の一覧の実物との突き合わせの試験`)が確かめる。

use crate::conform::design_ontology::line_matching::先頭の識別子;

/// 座標系を型引数に取る `blitz_math` のフレーム型1つ。型の名前と、型引数に取る座標系の数を持つ。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct フレーム型 {
    名前: &'static str,
    座標系の数: usize,
}

// 座標系を1つ取るフレーム型の名前の一覧。参照: `crates/blitz_math/src/frame/`。
const 座標系を1つ取る型の名前一覧: [&str; 15] = [
    "位置",
    "変位",
    "方向",
    "二段の位置",
    "角の勾配",
    "面積ベクトル",
    "慣性テンソル",
    "逆慣性テンソル",
    "速度",
    "角速度",
    "力",
    "回転力",
    "衝撃",
    "回転衝撃",
    "回転ベクトル",
];

// 座標系を2つ(入力の座標系と出力の座標系)取るフレーム型の名前の一覧。
const 座標系を2つ取る型の名前一覧: [&str; 2] = ["変換", "クォータニオン"];

impl フレーム型 {
    /// 一覧の全部。名前から探す関数と、実物との突き合わせの試験が読む。
    pub fn 一覧() -> impl Iterator<Item = フレーム型> {
        let 一つ = 座標系を1つ取る型の名前一覧.into_iter().map(|名前| フレーム型 { 名前, 座標系の数: 1 });
        一つ.chain(座標系を2つ取る型の名前一覧.into_iter().map(|名前| フレーム型 { 名前, 座標系の数: 2 }))
    }

    /// その名前が一覧に載ったフレーム型なら、その型を返す。
    pub fn 名前から探す(名前: &str) -> Option<フレーム型> {
        Self::一覧().find(|型| 型.名前 == 名前)
    }

    // 型の名前と座標系の数は試験だけが読む。抽出は名前から探した型を `表記が名指す型::フレーム型として読む` へ渡すだけで、中身を取り出さない。
    #[cfg(test)]
    pub fn 名前(&self) -> &'static str {
        self.名前
    }

    #[cfg(test)]
    pub fn 座標系の数(&self) -> usize {
        self.座標系の数
    }
}

/// 型の表記が名指す型。座標系を持たない型は名前だけを持ち、フレーム型は型引数に与えた座標系の名前の並びも持つ。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 表記が名指す型 {
    名前: String,
    座標系の一覧: Vec<String>,
}

impl 表記が名指す型 {
    /// 座標系を持たない型の名前から組む。
    pub fn 名前から生成する(名前: &str) -> Self {
        Self {
            名前: 名前.to_string(),
            座標系の一覧: Vec::new(),
        }
    }

    /// フレーム型の名前と、`<` と `>` の間の型引数の並びから組む。型引数が型の名前だけの並びでないか、数がその型の座標系の数と合わなければ無しである。
    pub fn フレーム型として読む(型: フレーム型, 型引数の並び: &str) -> Option<Self> {
        let 座標系の一覧: Vec<String> = 型引数の並び.split(',').map(|座標系| 座標系.trim().to_string()).collect();
        let 名前だけか = 座標系の一覧.iter().all(|座標系| !座標系.is_empty() && 先頭の識別子(座標系) == *座標系);
        (名前だけか && 座標系の一覧.len() == 型.座標系の数).then(|| Self {
            名前: 型.名前.to_string(), 座標系の一覧
        })
    }

    /// 定義を探すときの名前。座標系を落とした型の名前である。
    pub fn 定義を探す名前(&self) -> &str {
        &self.名前
    }

    /// 節点の同一性に使う名前。座標系を持つなら `変位<ワールド>` の形で含める。
    pub fn 同一性の名前(&self) -> String {
        if self.座標系の一覧.is_empty() {
            return self.名前.clone();
        }
        format!("{}<{}>", self.名前, self.座標系の一覧.join(", "))
    }

    /// 型の名前か座標系の名前のどれかが、定義の宣言が導入した型引数の名前と一致するなら、その名前を返す。
    pub fn 宣言の型引数と一致する名前(&self, 型引数名一覧: &[String]) -> Option<String> {
        std::iter::once(&self.名前).chain(&self.座標系の一覧).find(|名前| 型引数名一覧.contains(名前)).cloned()
    }
}
